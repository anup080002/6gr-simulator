function row = localQualifiedFRCRow(catalogHash, entryId, frcId, ...
        requiredSNR, measuredSNR, transportBlocks, blockErrors)
row = localDiagnosticFRCRow(catalogHash);
row.EntryId = string(entryId);
row.FRC = string(frcId);
row.Profile = "full";
row.Pass = true;
row.StatisticallyQualified = true;
row.OneSidedReferencePass = true;
row.PointEstimate = (transportBlocks - blockErrors) / transportBlocks;
row.OneSidedLower = max(0, row.PointEstimate - 0.002);
row.OneSidedUpper = min(1, row.PointEstimate + 0.002);
row.PointEstimatePass = true;
row.ObservedConfidenceBoundSupportsPass = true;
row.ConfidenceQualificationEligible = true;
row.RequiredSNR_dB = requiredSNR;
row.MeasuredSNR_dB = measuredSNR;
row.Delta_dB = measuredSNR - requiredSNR;
row.MeasuredSNRAvailable = true;
row.CrossingStatus = "resolved";
row.TransportBlocks = transportBlocks;
row.BlockErrors = blockErrors;
row.Transmissions = transportBlocks;
row.FailedTransmissionAttempts = blockErrors;
row.SweepTransportBlocks = transportBlocks;
row.SweepBlockErrors = blockErrors;
row.SweepTransmissions = transportBlocks;
row.SweepFailedTransmissionAttempts = blockErrors;
row.Status = "PASS";
row.FailureReason = "";
end

function ids = localCatalogEntryIds(catalog)
entries = catalog.entries;
ids = strings(numel(entries), 1);
for index = 1:numel(entries)
    if iscell(entries)
        entry = entries{index};
    else
        entry = entries(index);
    end
    ids(index) = string(entry.id);
end
end

