    "ProxyUsed", false, "FallbackUsed", false, ...
    "Status", "FAIL", "FailureIdentifier", "", ...
    "FailureReason", "observed_pass_not_statistically_qualified", ...
    "SourceGitCommit", string(repmat('c', 1, 40)), ...
    "SourceGitWorktreeDirty", false, "SourceMATLABRelease", "2026a", ...
