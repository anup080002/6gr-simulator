function ok = testLLSProductionQualificationReduction()
%TESTLLSPRODUCTIONQUALIFICATIONREDUCTION Final evidence must reduce fail closed.

setup6GRSimToolkit("Verbose", false);
catalog = sixgr.conformance.frcCatalog();
catalogHash = sixgr.util.sha256Hex(uint8(unicode2native( ...
    jsonencode(catalog), "UTF-8")));
root = tempname();
mkdir(fullfile(root,"reports","csv"));
mkdir(fullfile(root,"reports","json"));
cleanup = onCleanup(@()localRemove(root)); %#ok<NASGU>

status = struct("ResultOk",true,"ExecutionCompleted",true, ...
    "RuntimeTruthContractOk",true,"ScenarioObjectiveOk",true, ...
    "MandatorySubsystemsOk",true,"KpiConsistencyOk",true, ...
    "StatisticalQualificationOk",true,"StatisticalQualificationStatus","PASS", ...
    "PublicationLLSEligible",true);

reduced = sixgr.truth.applyProductionQualificationGate(status, root);
assert(reduced.FunctionalRunOk && ~reduced.ProductionGradeOk && ...
    ~reduced.PublicationReady && ~reduced.PublicationQualified);
assert(reduced.OverallQualificationStatus == ...
    "FUNCTIONAL_ONLY_NOT_PRODUCTION_QUALIFIED");

% A stale boolean cannot pass production statistics when its status
% authority is absent. Missing evaluation state must remain fail closed.
missingStatisticalState = rmfield(status, "StatisticalQualificationStatus");
reducedMissingStatisticalState = sixgr.truth.applyProductionQualificationGate( ...
    missingStatisticalState, root);
assert(~reducedMissingStatisticalState.StatisticalQualificationOk && ...
    reducedMissingStatisticalState.StatisticalQualificationStatus == ...
    "NOT_EVALUATED" && ...
    contains(reducedMissingStatisticalState.ProductionQualificationFailureReasons, ...
    "production_statistical_qualification_status_missing"), ...
    "A missing statistical status must not inherit a stale true boolean.");

% A bounded FRC diagnostic is real evaluated evidence, but it is not a
% statistically qualified production reference. The reducer must name
% that state instead of claiming that no FRC evaluation occurred.
diagnostic = table("dl_r_pdsch_1_1_4_fdd_awgn","R.1-1-4","AWGN", ...
    true,true,false,true,true,false,false,"diagnostic", ...
    "ACTUAL_FRC_FULL_STANDARD_TRUTH_EXECUTION",3.2,NaN,NaN,false, ...
    "not_evaluated_by_configuration",catalogHash,100,0,100,0, ...
    'VariableNames', {'EntryId','FRC','Condition','Required','ExecutionAttempted', ...
    'Pass','FullStandardExecutionExact','DataChannelExact', ...
    'StatisticallyQualified','OneSidedReferencePass','Profile','EvidenceClass', ...
    'RequiredSNR_dB','MeasuredSNR_dB','Delta_dB','MeasuredSNRAvailable', ...
    'CrossingStatus','CatalogSHA256','TransportBlocks','BlockErrors', ...
    'Transmissions','FailedTransmissionAttempts'});
writetable(diagnostic, fullfile(root,"reports","csv", ...
    "frc_reference_diagnostic.csv"));
reducedDiagnostic = sixgr.truth.applyProductionQualificationGate(status, root);
assert(reducedDiagnostic.ReferenceQualificationStatus == "FAIL" && ...
    contains(reducedDiagnostic.ProductionQualificationFailureReasons, ...
    "diagnostic_not_qualification_evidence"), ...
    "An executed diagnostic FRC campaign must be classified as evaluated but unqualified.");
diagnosticGate = readtable(fullfile(root,"reports","csv", ...
    "production_qualification_gate.csv"), "TextType", "string");
diagnosticRow = diagnosticGate.Gate == "IndependentFRCQualification";
assert(nnz(diagnosticRow) == 1 && ...
    diagnosticGate.Status(diagnosticRow) == "FAIL" && ...
    diagnosticGate.EvidenceArtifact(diagnosticRow) == ...
    "reports/csv/frc_reference_diagnostic.csv", ...
    "The production gate must point to the diagnostic evidence it inspected.");

% A smoke/diagnostic campaign may explicitly declare that independent FRC
% qualification is outside its production objective.  That authority must
% come from the persisted resolved config, must be visible in the gate, and
% must not turn the diagnostic into a pass.  Missing authority remains
% fail-closed as asserted above.
mkdir(fullfile(root,"meta"));
sixgr.util.jsonWrite(fullfile(root,"meta","scenario_config_resolved.json"), ...
    struct("validation",struct("independent_reference_qualification", ...
    struct("required_for_production",false))));
reducedOptionalReference = sixgr.truth.applyProductionQualificationGate(status, root);
assert(~reducedOptionalReference.ReferenceQualificationRequiredForProduction && ...
    ~reducedOptionalReference.ReferenceQualificationOk && ...
    reducedOptionalReference.ReferenceQualificationStatus == "NOT_EVALUATED" && ...
    ~contains(reducedOptionalReference.ProductionQualificationFailureReasons, ...
    "independent_frc_reference"), ...
    "An explicitly optional reference gate must be NOT_EVALUATED, never passed or failed.");
optionalGate = readtable(fullfile(root,"reports","csv", ...
    "production_qualification_gate.csv"), "TextType", "string");
optionalRow = optionalGate.Gate == "IndependentFRCQualification";
assert(nnz(optionalRow) == 1 && ~logical(optionalGate.Required(optionalRow)) && ...
    ~logical(optionalGate.Pass(optionalRow)) && ...
    optionalGate.Status(optionalRow) == "NOT_EVALUATED" && ...
    strlength(optionalGate.FailureReason(optionalRow)) == 0, ...
    "The optional reference row must preserve not-required/not-evaluated semantics.");
delete(fullfile(root,"meta","scenario_config_resolved.json"));

% A completed, truthful waveform whose statistical/scenario objective is
% not met remains a functional run. Scientific/publication qualification
% fails in its own dimension and must not create a circular runtime failure.
objectiveMiss = status;
objectiveMiss.ScenarioObjectiveOk = false;
reducedObjectiveMiss = sixgr.truth.applyProductionQualificationGate( ...
    objectiveMiss, root);
assert(reducedObjectiveMiss.FunctionalRunOk && ...
    ~reducedObjectiveMiss.ScenarioObjectiveQualificationOk && ...
    ~reducedObjectiveMiss.ScientificQualificationOk && ...
    reducedObjectiveMiss.OverallQualificationStatus == ...
    "FUNCTIONAL_ONLY_NOT_PRODUCTION_QUALIFIED", ...
    "Scientific objective failure must not relabel truth execution as failed.");

% Phase-7 owns its own aggregate gate.  If a versioned artifact contains
% both the phase aggregate and a legacy ResultOk alias, qualification must
% name Phase7Ok as the failing authority rather than ambiguously implying
% that the root runtime ResultOk failed.
writetable(table(false,true, ...
    'VariableNames', {'Phase7Ok','ResultOk'}), ...
    fullfile(root,"reports","csv","phase7_truth_gates.csv"));
reduced = sixgr.truth.applyProductionQualificationGate(status, root);
assert(contains(string(reduced.ProductionQualificationFailureReasons), ...
    "Phase7Ok_false") && ...
    ~contains(string(reduced.ProductionQualificationFailureReasons), ...
    "ResultOk_false"), ...
    "Production qualification must identify the Phase-7 aggregate gate.");

writetable(table(true,true,true,true,true,true,true,true,true,true, ...
    'VariableNames', {'ResultOk','Phase7Ok','Phase1Ok','Phase2Ok','Phase3Ok', ...
    'Phase4Ok','Phase5Ok','Phase6Ok','PublicationReadinessOk','Dummy'}), ...
    fullfile(root,"reports","csv","phase7_truth_gates.csv"));
writetable(table(true,true,true,true,true,true,true,true, ...
    'VariableNames', {'EnergyModelOk','PerformanceProfileOk','LongRunStabilityOk', ...
    'ArtifactCompletenessOk','PlotDataLineageOk','FinalScientificClaimsTruthfulOk', ...
    'PublicationReferenceComparisonOk','TerminalPublicationGatesOk'}), ...
    fullfile(root,"reports","csv","publication_readiness_gate_summary.csv"));
writetable(table([true;true],[true;true], ...
    'VariableNames', {'Required','Pass'}), ...
    fullfile(root,"reports","csv","phy_package_execution_evidence_gate.csv"));
entryIds = ["dl_r_pdsch_1_1_4_fdd_awgn"; ...
    "ul_g_fr1_a3a_1_awgn"];
sixgr.util.jsonWrite(fullfile(root,"meta","scenario_config_resolved.json"), ...
    struct("validation",struct("independent_reference_qualification", ...
    struct("required_for_production",true,"entry_ids",entryIds))));
writetable(table(entryIds,["R.1-1-4";"G-FR1-A3A-1"], ...
    ["AWGN";"AWGN"],[true;true],[true;true], ...
    [true;true],[true;true],[true;true],[true;true], ...
    [true;true],repmat("full",2,1), ...
    repmat("ACTUAL_FRC_FULL_STANDARD_TRUTH_EXECUTION",2,1), ...
    [-1;10],[-0.8;9.7],[0.2;-0.3], ...
    [true;true],repmat("resolved",2,1), ...
    repmat(catalogHash,2,1), ...
    [300000;10000],[3000;100],[300000;10000],[3000;100], ...
    'VariableNames', {'EntryId','FRC','Condition','Required','ExecutionAttempted', ...
    'Pass','FullStandardExecutionExact','DataChannelExact', ...
    'StatisticallyQualified','OneSidedReferencePass','Profile', ...
    'EvidenceClass','RequiredSNR_dB','MeasuredSNR_dB','Delta_dB', ...
    'MeasuredSNRAvailable','CrossingStatus','CatalogSHA256','TransportBlocks', ...
    'BlockErrors','Transmissions','FailedTransmissionAttempts'}), ...
    fullfile(root,"reports","csv","frc_reference_qualification.csv"));

reduced = sixgr.truth.applyProductionQualificationGate(status, root);
assert(reduced.FunctionalRunOk && reduced.WiringCoverageOk && ...
    reduced.NumericalValidationOk && reduced.ReferenceQualificationOk && ...
    reduced.ScientificQualificationOk && reduced.ProductionGradeOk && ...
    reduced.PublicationReady && reduced.PublicationQualified);
assert(reduced.OverallQualificationStatus == "PRODUCTION_QUALIFIED");
gate = readtable(fullfile(root,"reports","csv", ...
    "production_qualification_gate.csv"), "TextType","string");
assert(height(gate) == 9 && all(logical(gate.Pass(logical(gate.Required)))) && ...
    gate.Status(gate.Gate == "IndependentReferenceComparison") == "NOT_EVALUATED", ...
    "The v5 reducer must expose an optional independent-comparison row for non-sweep runs.");

% A fixed-SNR campaign cannot inherit NOT_APPLICABLE from the component
% PRACH/PDCCH statistical gate. Its production statistics are owned by the
% Phase-7 seed/campaign/CI/sample/sweep gates and must fail closed.
fixedStatus = status;
fixedStatus.RunClass = "fixed_snr_sweep_lls";
fixedStatus.StatisticalQualificationOk = true;
fixedStatus.StatisticalQualificationStatus = "NOT_APPLICABLE";
phase7Fixed = table(true,false,true,false,true,false,false, ...
    'VariableNames', {'SeedHierarchyOk','CampaignDesignOk', ...
    'CampaignCompletionOk','MultiSeedDropStatisticsOk', ...
    'ConfidenceIntervalsOk','SampleAdequacyOk','SweepDataQualityOk'});
writetable(phase7Fixed, fullfile(root,"reports","csv", ...
    "phase7_truth_gates.csv"));
reducedFixed = sixgr.truth.applyProductionQualificationGate(fixedStatus, root);
assert(~reducedFixed.StatisticalQualificationOk && ...
    reducedFixed.StatisticalQualificationStatus == "FAIL" && ...
    contains(reducedFixed.ProductionQualificationFailureReasons, ...
    "CampaignDesignOk|MultiSeedDropStatisticsOk|SampleAdequacyOk|SweepDataQualityOk"), ...
    "Fixed-SNR production statistics must be reduced from Phase-7 campaign evidence.");

phase7Fixed.CampaignDesignOk = true;
phase7Fixed.MultiSeedDropStatisticsOk = true;
phase7Fixed.SampleAdequacyOk = true;
phase7Fixed.SweepDataQualityOk = true;
writetable(phase7Fixed, fullfile(root,"reports","csv", ...
    "phase7_truth_gates.csv"));
reducedFixed = sixgr.truth.applyProductionQualificationGate(fixedStatus, root);
assert(reducedFixed.StatisticalQualificationOk && ...
    reducedFixed.StatisticalQualificationStatus == "PASS", ...
    "Complete fixed-SNR Phase-7 campaign statistics must satisfy the production statistical gate.");

% FRC qualification and the exact independent-reference comparison are
% separate contracts. A fixed-SNR campaign cannot hide a missing/failed
% exact comparison behind an optional FRC policy or a terminal aggregate.
sixgr.util.jsonWrite(fullfile(root,"meta","scenario_config_resolved.json"), ...
    struct("validation",struct("independent_reference_qualification", ...
    struct("required_for_production",false))));
publicationFixture = readtable(fullfile(root,"reports","csv", ...
    "publication_readiness_gate_summary.csv"), "TextType", "string");
publicationFixture.PublicationReferenceComparisonOk(:) = false;
publicationFixture.TerminalPublicationGatesOk(:) = false;
writetable(publicationFixture, fullfile(root,"reports","csv", ...
    "publication_readiness_gate_summary.csv"));
reducedFixedComparisonMiss = sixgr.truth.applyProductionQualificationGate( ...
    fixedStatus, root);
assert(~reducedFixedComparisonMiss.IndependentFRCQualificationRequiredForProduction && ...
    reducedFixedComparisonMiss.IndependentReferenceComparisonRequiredForProduction && ...
    ~reducedFixedComparisonMiss.IndependentReferenceComparisonOk && ...
    reducedFixedComparisonMiss.IndependentReferenceComparisonStatus == "FAIL" && ...
    ~reducedFixedComparisonMiss.ProductionGradeOk, ...
    "A fixed-SNR reference-comparison failure must remain explicit when FRC is optional.");
comparisonGate = readtable(fullfile(root,"reports","csv", ...
    "production_qualification_gate.csv"), "TextType", "string");
frcRow = comparisonGate.Gate == "IndependentFRCQualification";
comparisonRow = comparisonGate.Gate == "IndependentReferenceComparison";
assert(nnz(frcRow) == 1 && ~logical(comparisonGate.Required(frcRow)) && ...
    comparisonGate.Status(frcRow) == "NOT_EVALUATED" && ...
    nnz(comparisonRow) == 1 && logical(comparisonGate.Required(comparisonRow)) && ...
    ~logical(comparisonGate.Pass(comparisonRow)) && ...
    comparisonGate.Status(comparisonRow) == "FAIL", ...
    "The v5 table must preserve independent FRC and comparison semantics.");

% Restore passing independent evidence for the lifecycle assertions below.
sixgr.util.jsonWrite(fullfile(root,"meta","scenario_config_resolved.json"), ...
    struct("validation",struct("independent_reference_qualification", ...
    struct("required_for_production",true,"entry_ids",entryIds))));
publicationFixture.PublicationReferenceComparisonOk(:) = true;
publicationFixture.TerminalPublicationGatesOk(:) = true;
writetable(publicationFixture, fullfile(root,"reports","csv", ...
    "publication_readiness_gate_summary.csv"));

% Restore the generic Phase-7 fixture used by the lifecycle assertions.
writetable(table(true,true,true,true,true,true,true,true,true,true, ...
    'VariableNames', {'ResultOk','Phase7Ok','Phase1Ok','Phase2Ok','Phase3Ok', ...
    'Phase4Ok','Phase5Ok','Phase6Ok','PublicationReadinessOk','Dummy'}), ...
    fullfile(root,"reports","csv","phase7_truth_gates.csv"));

% ExecutionCompleted is owned by the canonical root lifecycle artifact and
% is not always repeated in the in-memory scenario reducer.  Its persisted
% value must be consumed rather than defaulted to false.
persisted = table(true, 'VariableNames', {'ExecutionCompleted'});
writetable(persisted, fullfile(root,"reports","csv", ...
    "result_status_summary.csv"));
statusWithoutLifecycle = rmfield(status, "ExecutionCompleted");
reduced = sixgr.truth.applyProductionQualificationGate( ...
    statusWithoutLifecycle, root);
assert(reduced.FunctionalRunOk && reduced.ProductionGradeOk, ...
    "Persisted execution-completion authority must satisfy the functional gate.");
persisted.ExecutionCompleted = false;
writetable(persisted, fullfile(root,"reports","csv", ...
    "result_status_summary.csv"));
reduced = sixgr.truth.applyProductionQualificationGate( ...
    statusWithoutLifecycle, root);
assert(~reduced.FunctionalRunOk && ~reduced.ProductionGradeOk, ...
    "A persisted incomplete execution must fail the production gate.");
gate = readtable(fullfile(root,"reports","csv", ...
    "production_qualification_gate.csv"), "TextType","string");
assert(~logical(gate.Pass(gate.Gate == "FunctionalRun")), ...
    "The persisted incomplete lifecycle must be visible in the gate table.");
ok = true;
fprintf("PASS testLLSProductionQualificationReduction: final production reduction is fail closed.\n");
end

function localRemove(pathValue)
if isfolder(pathValue), rmdir(pathValue,"s"); end
end
