function ok = testLLSCoupledTruthHARQRoundTrip()
%TESTLLSCOUPLEDTRUTHHARQROUNDTRIP Ensure coupled-truth HARQ replay reaches real retransmissions.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

baseScenario = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring.yaml");
scenarioPath = fullfile(tmp, "lls_coupled_truth_harq_roundtrip.yaml");
fid = fopen(scenarioPath, "w");
fprintf(fid, "%s", ['{' ...
    '"inherits":["' strrep(baseScenario, '\', '\\') '"],' ...
    '"meta":{"scenario_id":"lls_coupled_truth_harq_roundtrip","description":"coupled truth HARQ replay regression","version":"1","owner":"test","maturity_tag":"regression"},' ...
    '"simulation":{"link_direction":"both","n_frames":1,"n_slots":5,"monte_carlo_iterations":1,"random_seed":43,"snr_db":-5,"snr_sweep_offsets_db":[0]},' ...
    '"modulation":{"dl_modulation_order":4,"ul_modulation_order":4,"mcs_table":"qam64_table1","dl_mcs_index":14,"ul_mcs_index":14},' ...
    '"modulation_and_mapping":{"qam_order":4,"pdsch_modulation":"16QAM","pusch_modulation":"16QAM","dl_max_modulation":"16QAM","dl_mcs_index":14,"ul_mcs_index":14},' ...
    '"reference_signals":{"ssb_enabled":false,"pbch_enabled":false,"ssb_lmax":4,"ssb_Lmax":4,"pdsch_dmrs_ports":1,"pusch_dmrs_ports":1,"csi_rs_ports":1,"csi_rs_port_count":1,"csi_rs_resource_row_numbers":1,"csi_rs_resource_symbol_locations":5,"csi_rs_resource_subcarrier_locations":0,"csi_reporting_enabled":false,"cqi_reporting_enabled":false,"pmi_reporting_enabled":false,"ri_reporting_enabled":false,"cri_reporting_enabled":false,"pdsch_dmrs":{"num_ports":1,"port_set":[0]},"pusch_dmrs":{"num_ports":1,"port_set":[0]},"nzp_csi_rs":{"num_ports":1,"port_set":[0],"row_number":1,"symbol_location":5,"subcarrier_location":0},"srs":{"num_ports":1,"port_set":[0]},"csi_rs_precoder_codebook":{"enabled":true,"type":"dft_ura","physical_element_count":1,"beam_indices_port_0":0}},' ...
    '"antenna_and_array":{"bs_num_txrus":1,"bs_num_rxrus":1,"ue_num_txrus":1,"ue_num_rxrus":1,"bs_num_antenna_elements":1,"ue_num_antenna_elements":1},' ...
    '"mimo":{"n_tx_ant":1,"n_rx_ant":1,"n_layers":1,"max_dl_layers":1,"max_ul_layers":1,"beam_sweep_enabled":false,"beam_management_enable":false,"beam_count":1,"phase07_strict":{"enabled":false,"max_rank":1,"rank_domain":[1]}},' ...
    '"link_adaptation":{"operating_point_mode":"fixed","fixed_or_amc":"fixed","pdsch_link_adaptation_policy":"fixed","pusch_link_adaptation_policy":"fixed","rank_adaptation_policy":"fixed","beam_adaptation_policy":"fixed"},' ...
    '"pdsch":{"execution_profile":"scheduler_truth","fixed_mcs":14,"link_adaptation_mode":"fixed","layer_count":1,"rank":1,"num_antenna_ports":1},' ...
    '"pusch":{"execution_profile":"scheduler_truth","fixed_mcs":14,"mcs_index":14,"transmission_scheme":"nonCodebook","codebook_based_transmission":false,"layer_count":1,"num_layers":1,"num_antenna_ports":1},' ...
    '"run_control":{"total_slots":5,"warmup_slots":0,"measurement_slots":5,"total_time_ms":5,"warmup_time_ms":0,"measurement_time_ms":5,"batch_size_links":1,"num_workers":1},' ...
    '"energy_efficiency":{"tx_power_dbm":-35},' ...
    '"power_and_rf_frontend":{"bs_tx_power_dbm":-35,"ue_tx_power_dbm":-35,"ue_noise_figure_db":9,"power_backoff_db":0,"pa_model":"ideal","pa_efficiency_model":"constant","pa_nonlinearity_model":"none","cfr_enabled":false,"dpd_enabled":false,"dac_resolution_bits":12,"adc_resolution_bits":12,"iq_imbalance":"none","dc_offset":"none","lo_phase_noise_model":"none","cfo_model":"constant_zero","drift_rate_model":"none","rf_switching_latency":0,"noise_figure":9,"rx_gain_control":"fixed","saturation_model":"none"},' ...
    '"users":{"enabled":true,"n_users":1,"rnti_start":401,"seed_stride":11,"execution_model":"slot_coupled_truth","beam_selection_strategy":"fixed_first_beam","save_user_tables":true},' ...
    '"harq":{"enabled":true,"feedback_timing_slots":1,"max_retx":3,"rv_sequence":[0,2,3,1],"combining_mode":"soft"},' ...
    '"rf_frontend":{"ul_power_control":{"require_measured_reference_rs":false}},' ...
    '"pucch_resources":{"power_control":{"require_measured_reference_rs":false}},' ...
    '"initial_access":{"enabled":false,"ssb":{"enabled":false,"lmax":4,"beam_count":4,"positions_in_burst":"1111","precoder_ids":["siso_beam_0","siso_beam_1","siso_beam_2","siso_beam_3"],"precoder_codebook":{"enabled":false,"type":"dft_ura","physical_element_count":1,"beam_grid_rows":1,"beam_grid_columns":4,"beam_indices":[0,1,2,3]},"waveform_domain":"logical_port_domain"},"mib":{"enabled":false},"sib1":{"enabled":false}},' ...
    '"random_access":{"enabled":false},' ...
    '"control_gating":{"pbch_required":false,"prach_required":false,"pdcch_required":false,"srs_required":false,"srs_max_age_slots":4,"trs_required":false,"trs_max_age_slots":4},' ...
    '"system":{"scheduler":{"coverageOutageGuardEnabled":false,"minSchedulingSINR_dB":-100}},' ...
    '"sweeps_and_matrix":{"snr_sweep":{"enabled":false,"values_db":[]}},' ...
    '"output_control":{"save_raw_waveforms":false,"save_llrs":false,"save_channel_snapshots":false,"save_constellations":false,"save_debug_events":false,"save_plots":false},' ...
    '"output":{"save_figures":false,"save_mat":false,"save_png":false,"phy_signal_diagnostic_enabled":false,"profile":"lls_coupled_truth_harq_roundtrip","live_publish_frame_interval":1,"live_heavy_refresh_interval_frames":10}}']);
fclose(fid);

scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "preflight"));
slotDuration_s = max(eps, double(sixgr.util.structGet(cfg, "phy.numerology.slotDuration_ms", 0.5)) / 1e3);
opt = struct( ...
    "LinkDuration_s", max(double(cfg.run.totalSlots) * slotDuration_s, slotDuration_s), ...
    "LinkMaxSimFrames", double(cfg.run.totalSlots), ...
    "LinkSNR_dB", double(cfg.channel.snr_dB), ...
    "LinkSNRGrid_dB", double(cfg.channel.snr_dB), ...
    "LinkSweepFrames", 1, ...
    "LinkSweepTrialsPerSNR", double(cfg.run.totalSlots), ...
    "LinkReferenceSweepFrames", double(cfg.run.totalSlots), ...
    "LinkSweepMaxPoints", 1, ...
    "LinkAdaptiveSweepEnabled", false, ...
    "LinkAdaptiveSweepStep_dB", 2, ...
    "LinkAdaptiveSweepMaxPoints", 1, ...
    "SaveFigures", false);

airInterfaceFolder = fullfile(tmp, "bundle", "air_interface");
out = sixgr.truth.runWaveformLinkBundle(cfg, airInterfaceFolder, opt);
assert(isstruct(out), "Coupled-truth HARQ roundtrip must return a runtime output struct.");

runFolder = fileparts(airInterfaceFolder);
dlFile = fullfile(airInterfaceFolder, "csv", "dl_pdsch_trials.csv");
ulFile = fullfile(airInterfaceFolder, "csv", "ul_pusch_trials.csv");
harqFile = fullfile(runFolder, "harq", "csv", "live_harq_observation_timeline.csv");
stageFile = fullfile(airInterfaceFolder, "reports", "csv", "live_stage_status.csv");

assert(exist(dlFile, "file") == 2, "Coupled-truth HARQ roundtrip must write DL trials.");
assert(exist(ulFile, "file") == 2, "Coupled-truth HARQ roundtrip must write UL trials.");
assert(exist(harqFile, "file") == 2, "Coupled-truth HARQ roundtrip must write live HARQ timeline.");
assert(exist(stageFile, "file") == 2, "Coupled-truth HARQ roundtrip must write live stage status.");

dl = readtable(dlFile, "VariableNamingRule", "preserve");
ul = readtable(ulFile, "VariableNamingRule", "preserve");
harq = readtable(harqFile, "VariableNamingRule", "preserve");
stage = readtable(stageFile, "VariableNamingRule", "preserve");

assert(~isempty(dl), "Coupled-truth HARQ roundtrip DL trials must not be empty.");
assert(~isempty(ul), "Coupled-truth HARQ roundtrip UL trials must not be empty.");
assert(~isempty(harq), "Coupled-truth HARQ roundtrip HARQ timeline must not be empty.");
slotsPerFrame = max(1, round(double(sixgr.util.structGet(cfg, "phy.numerology.slotsPerFrame", 10))));
expectedULFrame = floor(max(0, double(ul.Slot) - 1) ./ slotsPerFrame) + 1;
assert(all(double(ul.Frame) == expectedULFrame), ...
    "Queued UL K2 grants must stamp Frame from the absolute scheduled slot, not copy the slot index.");
assert(any(logical(harq.IsRetransmission)), "Coupled-truth HARQ roundtrip must exercise a real retransmission.");
assert(~any(string(dl.Status) == "CRASH") && ~any(string(ul.Status) == "CRASH"), ...
    "Coupled-truth HARQ roundtrip must not crash data-plane waveform trials.");
assert(max(double(stage.DLCompletedFrames)) >= 1, "Coupled-truth HARQ roundtrip must advance DL frames.");
assert(max(double(stage.ULCompletedFrames)) >= 1, "Coupled-truth HARQ roundtrip must advance UL frames.");

fprintf("PASS testLLSCoupledTruthHARQRoundTrip: DL=%d UL=%d HARQ=%d.\n", ...
    height(dl), height(ul), height(harq));
ok = true;
end
