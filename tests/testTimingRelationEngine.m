function coverage = localExerciseCatalogTimingRows()
supportedMu = [0, 1, 2, 3, 5, 6];
tdra = sixgr.phy.frame.TimeDomainResourceAllocationCatalog.selectedRows();
channels = string({tdra.Channel});
pdsRows = tdra(channels == "PDSCH");
pusRows = tdra(channels == "PUSCH");
catalogK0 = unique([pdsRows.K0], "stable");
catalogK0 = catalogK0(isfinite(catalogK0));
catalogK2 = unique([pusRows.K2], "stable");
catalogK2 = catalogK2(isfinite(catalogK2));
assert(isequal(catalogK0, [0, 1]) && isequal(catalogK2, 1), ...
    "Selected TDRA catalog timing rows changed without test review.");

coverage = struct("Numerologies", 0, "K0Rows", 0, ...
    "K1Rows", 0, "K2Rows", 0, "CapabilityChecks", 0);
for mu = supportedMu
    [carrier, dl, ul] = localCatalogCarrier(mu);
    capability = sixgr.phy.frame.TimingPolicyCatalog.capability1(mu);
    catalogK1 = sixgr.phy.frame.TimingPolicyCatalog.defaultK1Values(mu);
    legalK2 = ceil((capability.PUSCHN2Symbols + 1) / ...
        ul.SymbolsPerSlot);
    policy = struct( ...
        "AllowedK0", catalogK0, ...
        "AllowedK1", catalogK1, ...
        "AllowedK2", unique([catalogK2, legalK2], "stable"), ...
        "PolicyID", "catalog-exhaustion-mu" + string(mu), ...
        "Source", "pinned_release18_catalog_test");
    engine = sixgr.phy.frame.TimingRelationEngine(carrier, policy);
    source = sixgr.phy.frame.AbsoluteTime.fromAbsoluteSlotSymbol( ...
        1000, 0, dl);

    for rowIndex = 1:numel(pdsRows)
        row = pdsRows(rowIndex);
        request = localRequest("catalog-" + lower(row.ID) + ...
            "-mu" + string(mu), "PDSCH", source, ...
            "DL0", "DL0", row.K0, row.StartSymbol, ...
            row.NumSymbols, 0);
        result = engine.resolvePDSCH(request);
        assert(result.Valid && result.K0 == row.K0 && ...
            result.TargetMu == mu, ...
            "Catalog row %s failed at mu=%d: %s.", ...
            row.ID, mu, result.ReasonCode);
        coverage.K0Rows = coverage.K0Rows + 1;
    end

    for k1 = catalogK1
        request = localRequest("catalog-k1-mu" + string(mu) + ...
            "-k" + string(k1), "HARQ_ACK", source, ...
            "DL0", "UL0", k1, 0, 1, 0);
        request.SourceNumSymbols = 1;
        result = engine.resolveHARQACK(request);
        assert(result.Valid && result.K1 == k1 && ...
            result.TargetMu == mu, ...
            "Catalog K1=%d failed at mu=%d: %s.", ...
            k1, mu, result.ReasonCode);
        coverage.K1Rows = coverage.K1Rows + 1;
    end

    for rowIndex = 1:numel(pusRows)
        row = pusRows(rowIndex);
        request = localRequest("catalog-" + lower(row.ID) + ...
            "-mu" + string(mu), "PUSCH", source, ...
            "DL0", "UL0", row.K2, row.StartSymbol, ...
            row.NumSymbols, 0);
        request.SourceNumSymbols = 1;
        result = engine.resolvePUSCH(request);
        assert(result.Valid && result.K2 == row.K2 && ...
            result.TargetMu == mu, ...
            "Catalog row %s failed at mu=%d: %s.", ...
            row.ID, mu, result.ReasonCode);
        coverage.K2Rows = coverage.K2Rows + 1;
    end

    legalN1 = localRequest("capability-n1-legal-mu" + string(mu), ...
        "HARQ_ACK", source, "DL0", "UL0", max(catalogK1), ...
        0, 1, capability.PDSCHN1Symbols);
    legalN1.SourceNumSymbols = 1;
    legalN1.ProcessingTimeReference = ...
        capability.PDSCHProcessingTimeReference;
    legalN1Result = engine.resolveHARQACK(legalN1);
    assert(legalN1Result.Valid, ...
        "Pinned N1=%d should be feasible at mu=%d and K1=%d: %s.", ...
        capability.PDSCHN1Symbols, mu, max(catalogK1), ...
        legalN1Result.ReasonCode);

    illegalN1 = legalN1;
    illegalN1.TestID = "capability-n1-illegal-mu" + string(mu);
    illegalN1.K1 = min(catalogK1);
    illegalN1.MinimumProcessingSymbols = ...
        capability.PDSCHN1Symbols + 10000;
    illegalN1Result = engine.resolveHARQACK(illegalN1);
    assert(~illegalN1Result.Valid && ...
        illegalN1Result.ReasonCode == ...
            "insufficient_n1_processing_time", ...
        "Illegal N1 case at mu=%d returned valid=%d reason=%s.", ...
        mu, illegalN1Result.Valid, illegalN1Result.ReasonCode);

    legalN2 = localRequest("capability-n2-legal-mu" + string(mu), ...
        "PUSCH", source, "DL0", "UL0", legalK2, ...
        0, 1, capability.PUSCHN2Symbols);
    legalN2.SourceNumSymbols = 1;
    legalN2.ProcessingTimeReference = ...
        capability.PUSCHProcessingTimeReference;
    legalN2Result = engine.resolvePUSCH(legalN2);
    assert(legalN2Result.Valid, ...
        "Pinned N2=%d should be feasible at mu=%d and K2=%d: %s.", ...
        capability.PUSCHN2Symbols, mu, legalK2, ...
        legalN2Result.ReasonCode);

    illegalN2 = legalN2;
    illegalN2.TestID = "capability-n2-illegal-mu" + string(mu);
    illegalN2.K2 = catalogK2(1);
    illegalN2.MinimumProcessingSymbols = ...
        capability.PUSCHN2Symbols + 10000;
    illegalN2Result = engine.resolvePUSCH(illegalN2);
    assert(~illegalN2Result.Valid && ...
        illegalN2Result.ReasonCode == ...
            "insufficient_n2_processing_time", ...
        "Illegal N2 case at mu=%d returned valid=%d reason=%s.", ...
        mu, illegalN2Result.Valid, illegalN2Result.ReasonCode);

    coverage.Numerologies = coverage.Numerologies + 1;
    coverage.CapabilityChecks = coverage.CapabilityChecks + 4;
end
end

function [carrier, dl, ul] = localCatalogCarrier(mu)
[range, centerHz, bandwidthMHz, nrb] = localCatalogGridRow(mu);
scsKHz = 15 * 2^mu;
grid = struct("NStartGrid", 0, "NSizeGrid", nrb, ...
    "SubcarrierSpacingKHz", scsKHz, ...
    "CyclicPrefix", "normal", "FrequencyRange", range);
zero = sixgr.phy.frame.AbsoluteTime.fromTicks(0);
dl = sixgr.phy.frame.BWPConfig(localCatalogBWP( ...
    "DL0", "DL", range, scsKHz, nrb, zero), grid);
ul = sixgr.phy.frame.BWPConfig(localCatalogBWP( ...
    "UL0", "UL", range, scsKHz, nrb, zero), grid);
cfg = struct( ...
    "CCID", "CC0", "ServingCellID", "CELL0", ...
    "SchedulingCCIDs", "CC0", ...
    "CenterFrequencyHz", centerHz, ...
    "DLCenterFrequencyHz", centerHz, ...
    "ULCenterFrequencyHz", centerHz - 100e6, ...
    "Band", "catalog_test", "FrequencyRange", range, ...
    "ChannelBandwidthMHz", bandwidthMHz, "DuplexMode", "FDD", ...
    "DLCarrierGrid", grid, "ULCarrierGrid", grid, ...
    "CarrierIndicatorMap", struct( ...
        "Indicator", 0, "ScheduledCCID", "CC0"));
carrier = sixgr.phy.frame.ComponentCarrierConfig(cfg, {dl, ul});
end

