function ok = testTimingRelationEngine()
%TESTTIMINGRELATIONENGINE Exact K0/K1/K2 and TDD/BWP rejection reasons.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
[cc, dl0, ul1, state30, state60] = localFixture();
cc.setAvailabilityResolver(@(carrier, bwp, time, startSymbol, ...
    numSymbols, direction) localAvailability(carrier, bwp, time, ...
    startSymbol, numSymbols, direction, state30, state60));

activation = sixgr.phy.frame.AbsoluteTime.fromAbsoluteSlotSymbol( ...
    10, 0, ul1);
switchDecision = cc.BWPState.scheduleSwitch( ...
    "UL", "UL1", activation, ...
    "IssuedTime", sixgr.phy.frame.AbsoluteTime.fromTicks(0), ...
    "ControlBWPID", "DL0", ...
    "TriggerSource", "RRC", ...
    "CommandID", "activate-ul60");
assert(switchDecision.Accepted);

policy = struct( ...
    "AllowedK0", [0, 1, 3], ...
    "AllowedK1", [1, 18], ...
    "AllowedK2", [1, 8, 18, 21], ...
    "PolicyID", "focused_release18_timing_rows", ...
    "Source", "validated_test_policy");
engine = sixgr.phy.frame.TimingRelationEngine(cc, policy);

sourceControl = sixgr.phy.frame.AbsoluteTime.fromFrameSlotSymbol( ...
    0, 0, 0, dl0);
pdsch = localRequest("same-numerology-pdsch", "PDSCH", ...
    sourceControl, "DL0", "DL0", 1, 2, 10, 0);
rPDSCH = engine.resolvePDSCH(pdsch);
assert(rPDSCH.Valid && rPDSCH.ReasonCode == "timing_relation_valid");
assert(rPDSCH.SourceMu == 1 && rPDSCH.TargetMu == 1 && ...
    rPDSCH.TargetAbsoluteSlot == 1);

opposite = localRequest("fixed-opposite-pusch", "PUSCH", ...
    sourceControl, "DL0", "UL1", 21, 0, 4, 0);
rOpposite = engine.resolvePUSCH(opposite);
assert(~rOpposite.Valid && ...
    rOpposite.ReasonCode == "target_hits_fixed_opposite_direction", ...
    "A fixed-DL target must reject a PUSCH grant without time repair.");

beforeActivation = localRequest("early-ul60", "PUSCH", ...
    sourceControl, "DL0", "UL1", 8, 0, 4, 0);
rBefore = engine.resolvePUSCH(beforeActivation);
assert(~rBefore.Valid && ...
    rBefore.ReasonCode == "target_bwp_inactive_at_target_time");

mixed = localRequest("mixed-numerology-pusch", "PUSCH", ...
    sourceControl, "DL0", "UL1", 18, 0, 10, 2);
rMixed = engine.resolvePUSCH(mixed);
assert(rMixed.Valid && rMixed.SourceMu == 1 && rMixed.TargetMu == 2);
assert(rMixed.TargetAbsoluteSlot == 18 && ...
    rMixed.AvailabilityReasonCode == "available");
assert(rMixed.TargetTick == ...
    sixgr.phy.frame.AbsoluteTime.fromAbsoluteSlotSymbol( ...
    18, 0, ul1).tickValue());

n2 = mixed;
n2.TestID = "insufficient-n2";
n2.MinimumProcessingSymbols = 1000;
rN2 = engine.resolvePUSCH(n2);
assert(~rN2.Valid && rN2.ReasonCode == ...
    "insufficient_n2_processing_time");

harqSource = sixgr.phy.frame.AbsoluteTime.fromFrameSlotSymbol( ...
    0, 0, 2, dl0);
harq = localRequest("mixed-numerology-harq", "HARQ_ACK", ...
    harqSource, "DL0", "UL1", 18, 0, 2, 2);
harq.SourceNumSymbols = 10;
harq.HARQProcessID = 3;
rHARQ = engine.resolveHARQACK(harq);
assert(rHARQ.Valid && rHARQ.K1 == 18 && rHARQ.TargetMu == 2);

n1 = harq;
n1.TestID = "insufficient-n1";
n1.MinimumProcessingSymbols = 1000;
rN1 = engine.resolveHARQACK(n1);
assert(~rN1.Valid && rN1.ReasonCode == ...
    "insufficient_n1_processing_time");

flex = localRequest("unresolved-flex", "PDSCH", ...
    sourceControl, "DL0", "DL0", 3, 0, 4, 0);
rFlex = engine.resolvePDSCH(flex);
assert(~rFlex.Valid && rFlex.ReasonCode == ...
    "target_flexible_symbols_unresolved");

allocation = struct( ...
    "AbsoluteSlot", 3, ...
    "StartSymbol", 0, ...
    "NumSymbols", 4, ...
    "Direction", "DL", ...
    "Channel", "PDSCH", ...
    "DecisionSource", "test_scheduler");
state30 = sixgr.phy.frame.FlexibleSymbolAllocator.allocate( ...
    state30, allocation);
cc.setAvailabilityResolver(@(carrier, bwp, time, startSymbol, ...
    numSymbols, direction) localAvailability(carrier, bwp, time, ...
    startSymbol, numSymbols, direction, state30, state60));
rResolved = engine.resolvePDSCH(flex);
assert(rResolved.Valid && rResolved.ReasonCode == "timing_relation_valid");

badK = mixed;
badK.TestID = "unsupported-k2";
badK.K2 = 7;
rBadK = engine.resolvePUSCH(badK);
assert(~rBadK.Valid && rBadK.ReasonCode == "unsupported_k2", ...
    "An unsupported K value must not be repaired to a later slot.");

trace = engine.traceTable();
assert(height(trace) == 10 && ...
    all(strlength(trace.ReasonCode) > 0) && ...
    all(trace.Status == "PASS" | trace.Status == "REJECTED"));
assert(any(trace.ReasonCode == "target_flexible_symbols_unresolved") && ...
    any(trace.ReasonCode == "insufficient_n1_processing_time") && ...
    any(trace.ReasonCode == "insufficient_n2_processing_time"));

% Exhaust the pinned timing catalogs across every supported processing
% capability numerology.  K0/K2 come from every selected TDRA catalog row;
% K1 comes from every Release-18 default-K1 row for that numerology.
coverage = localExerciseCatalogTimingRows();
assert(coverage.Numerologies == 6 && ...
    coverage.K0Rows == 24 && coverage.K1Rows == 48 && ...
    coverage.K2Rows == 12 && coverage.CapabilityChecks == 24, ...
    "The programmatic timing catalog coverage is incomplete.");

tmp = string(tempname);
mkdir(tmp);
cleanup = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>
csvPath = fullfile(tmp, "timing_matrix.csv");
writetable(trace, csvPath);
assert(isfile(csvPath) && dir(csvPath).bytes > 0);
imagePath = fullfile(tmp, "k0_k1_k2_timeline.png");
fig = figure("Visible", "off");
figCleanup = onCleanup(@() close(fig)); %#ok<NASGU>
validRows = trace.TargetTick >= 0;
scatter(double(trace.SourceTick(validRows)), ...
    double(trace.TargetTick(validRows)), 35, ...
    double(trace.Valid(validRows)), "filled");
xlabel("source absolute tick");
ylabel("target absolute tick");
title("K0 / K1 / K2 exact timing");
grid on;
exportgraphics(fig, imagePath, "Resolution", 120);
assert(isfile(imagePath) && dir(imagePath).bytes > 1000);

ok = true;
end

function request = localRequest(testID, procedure, sourceTime, ...
        sourceBWPID, targetBWPID, k, targetStart, targetLength, ...
        minimumProcessingSymbols)
request = struct( ...
    "TestID", testID, ...
    "Procedure", procedure, ...
    "SourceTime", sourceTime, ...
    "SchedulingCCID", "CC0", ...
    "ScheduledCCID", "CC0", ...
    "CarrierIndicator", 0, ...
    "SourceBWPID", sourceBWPID, ...
    "TargetBWPID", targetBWPID, ...
    "SourceNumSymbols", 2, ...
    "TargetStartSymbol", targetStart, ...
    "TargetNumSymbols", targetLength, ...
    "MinimumProcessingSymbols", minimumProcessingSymbols, ...
    "ProcessingTimeReference", "source", ...
    "TimingAdvanceTicks", 0, ...
    "HARQProcessID", 0);
switch upper(procedure)
    case "PDSCH"
        request.K0 = k;
    case "PUSCH"
        request.K2 = k;
    otherwise
        request.K1 = k;
end
end

