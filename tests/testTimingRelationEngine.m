function [range, centerHz, bandwidthMHz, nrb] = ...
        localCatalogGridRow(mu)
switch mu
    case 0
        range = "FR1"; centerHz = 4e9; bandwidthMHz = 3; nrb = 15;
    case 1
        range = "FR1"; centerHz = 4e9; bandwidthMHz = 10; nrb = 24;
    case 2
        range = "FR1"; centerHz = 4e9; bandwidthMHz = 20; nrb = 24;
    case 3
        range = "FR2-1"; centerHz = 28e9; bandwidthMHz = 50; nrb = 32;
    case 5
        range = "FR2-2"; centerHz = 60e9; bandwidthMHz = 400; nrb = 66;
    case 6
        range = "FR2-2"; centerHz = 60e9; bandwidthMHz = 400; nrb = 33;
    otherwise
        error("sixgr:test:UnsupportedCatalogMu", ...
            "No test carrier row is configured for mu=%d.", mu);
end
end
