function result = localAvailability(~, bwp, slotStart, startSymbol, ...
        numSymbols, direction, state30, state60)
[frame, slot, ~, aligned] = slotStart.toNumerology(bwp);
if ~aligned
    result = struct( ...
        "Available", false, ...
        "ReasonCode", "slot_start_not_numerology_aligned", ...
        "ObservedDirections", "UNKNOWN", ...
        "DuplexMode", "TDD");
    return;
end
absoluteSlot = double(frame) * bwp.SlotsPerFrame + double(slot);
if bwp.SCSKHz == 30
    state = state30;
else
    state = state60;
end
result = sixgr.phy.frame.SlotFormatResolver.isAvailable( ...
    state, absoluteSlot, startSymbol, numSymbols, direction);
end

