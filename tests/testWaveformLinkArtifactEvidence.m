function ok = testWaveformLinkArtifactEvidence()
%TESTWAVEFORMLINKARTIFACTEVIDENCE Runtime trials drive BLER CSV evidence.

n = 8;
snr = repelem([-5; 0; 5; 10], 2);
hash = repmat(string(repmat('a', 1, 64)), n, 1);
raw = table( ...
    snr, repmat("AWGN", n, 1), repmat(2, n, 1), ...
    repmat(10, n, 1), repmat("64QAM", n, 1), ...
    logical([0;1;0;1;1;1;1;1]), repmat("unit_scenario", n, 1), ...
    hash, true(n,1), true(n,1), true(n,1), false(n,1), false(n,1), ...
    repmat("real_lls_evidence", n, 1), ...
    'VariableNames', ["ConfiguredSNR_dB","ChannelModelApplied", ...
    "Rank","MCSIndex","Modulation","CRCPass","ScenarioID", ...
    "ConfigHash","FinalizedFlag","CRCApplicable","DecodeAttempted", ...
    "FallbackFlag","PlaceholderFlag","TruthStatus"]);
ul = raw;
ul.TransformPrecodingApplied = false(n,1);
ul.FrequencyHoppingApplied = true(n,1);
ul.FrequencyHoppingMode = repmat("intra_slot", n, 1);
result = struct("Link", struct("RawTrials", struct("DL", raw, "UL", ul)));
scfg = struct("scenario_id", "unit_scenario", "ConfigHash", hash(1));
cfg = struct();
cfg.run.runTag = "unit_run";
cfg.frequency.centerFrequencyHz = 3.5e9;
cfg.frequency.bandwidthHz = 100e6;
cfg.channel.subcarrierSpacing_kHz = 30;
cfg.validation.fixed_link_campaign = struct( ...
    "enabled", true, "min_tb_per_point", 2, ...
    "min_errors_for_ci", 0, "max_ci_half_width", 1, ...
    "confidence_level", 0.95);

registry = sixgr.artifact.EvidenceRegistry();
coverage = sixgr.artifact.registerWaveformLinkEvidence( ...
    registry, result, scfg, cfg, struct("RunID", "unit_run"));
assert(any(coverage.Registered & coverage.FileName == "pdsch_bler_curve.csv"));
assert(any(coverage.Registered & coverage.FileName == "pusch_bler_curve.csv"));
[found, curve, provenance] = registry.resolveTable( ...
    "pdsch", "base", "pdsch_bler_curve.csv");
assert(found && height(curve) == 4);
assert(all(curve.Trials == 2) && all(curve.CILower >= 0) && ...
    all(curve.CIUpper <= 1));
assert(all(curve.Status == "STATISTICALLY_QUALIFIED"));
assert(contains(provenance, "registerWaveformLinkEvidence"));
sixgr.artifact.validateEvidenceIdentity(curve, struct( ...
    "ScenarioID", "unit_scenario", "ConfigHash", hash(1), ...
    "EvidenceScope", "in_path", "RunID", "unit_run", ...
    "ExecutionID", "", "CenterFrequencyHz", 3.5e9, ...
    "BandwidthHz", 100e6, "SubcarrierSpacingHz", 30e3), ...
    "pdsch_bler_curve.csv");

[rendererFound, ~] = registry.resolveRenderer( ...
    "pdsch", "base", "pdsch_bler_vs_snr.png");
assert(~rendererFound, ...
    "The retired MATLAB PDSCH BLER renderer must not be registered.");

[ulFound, ulCurve] = registry.resolveTable( ...
    "pusch", "base", "pusch_bler_curve.csv");
assert(ulFound && height(ulCurve) == 4);
assert(all(ulCurve.TransformPrecoding == false));
assert(all(ulCurve.FrequencyHopping == "intra_slot"));
assert(all(ulCurve.Status == "STATISTICALLY_QUALIFIED") & ...
    ~any(ulCurve.Incomplete));
[ulRendererFound, ~] = registry.resolveRenderer( ...
    "pusch", "base", "pusch_bler_vs_snr.png");
assert(~ulRendererFound, ...
    "The retired MATLAB PUSCH BLER renderer must not be registered.");

% A bounded scenario observation is still valid in-path truth when it does
% not claim statistical qualification.  Its Status must say MEASURED and
% its stop reason must preserve the explicit non-qualification scope.
cfg.validation.fixed_link_campaign.enabled = false;
measuredRegistry = sixgr.artifact.EvidenceRegistry();
measuredCoverage = sixgr.artifact.registerWaveformLinkEvidence( ...
    measuredRegistry, result, scfg, cfg, struct("RunID", "unit_run"));
assert(all(measuredCoverage.Registered));
[measuredFound, measuredDL] = measuredRegistry.resolveTable( ...
    "pdsch", "base", "pdsch_bler_curve.csv");
[measuredULFound, measuredUL] = measuredRegistry.resolveTable( ...
    "pusch", "base", "pusch_bler_curve.csv");
assert(measuredFound && measuredULFound);
assert(all(measuredDL.Status == "MEASURED") && ...
    ~any(measuredDL.Incomplete) && ...
    all(measuredDL.StopReason == ...
        "fixed_sample_runtime_observation_not_qualification_campaign"));
assert(all(measuredUL.Status == "MEASURED") && ...
    ~any(measuredUL.Incomplete));

ok = true;
fprintf("PASS testWaveformLinkArtifactEvidence: exact in-memory BLER evidence registered.\n");
end
