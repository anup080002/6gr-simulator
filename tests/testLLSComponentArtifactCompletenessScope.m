function ok = testLLSComponentArtifactCompletenessScope()
%TESTLLSCOMPONENTARTIFACTCOMPLETENESSSCOPE Full-LLS plots do not gate PRACH-only runs.

setup6GRSimToolkit("Verbose", false);
ctx = llsRootGateFixture("honest_study");
scfg = sixgr.util.structSet(ctx.ScenarioConfig, ...
    "scenario.runner_profile", "prach_detection");
scfg = sixgr.util.structSet(scfg, ...
    "scenario.scenario_mode", "adaptive_link");
scfg = sixgr.util.structSet(scfg, ...
    "scenario.honesty_mode", "component_measurement");
cfg = sixgr.util.structSet(ctx.InternalConfig, ...
    "run.runnerProfile", "prach_detection");
cfg = sixgr.util.structSet(cfg, ...
    "phy.linkAdaptation.mode", "adaptive_link");

% This is a publication-readiness result for a complete LLS run.  It is
% intentionally false and must remain visible as a diagnostic, but it must
% not impose unrelated PDSCH/throughput/energy plots on a PRACH component
% runner.
T = table("reports/image/bler_vs_measured_sinr.png", 1, false, ...
    "mandatory_full_lls_artifact_missing", ...
    'VariableNames', {'MissingArtifacts','RequiredArtifactCount', ...
    'ArtifactCompletenessOk','FailureReason'});
sixgr.util.csvWriteTable(fullfile(ctx.Layout.ReportCSVDir, ...
    "artifact_completeness_summary.csv"), T);

verdict = struct("Failures", strings(0, 1), ...
    "CanonicalArtifactGapCount", 0, "RoundtripMismatchCount", 0, ...
    "CheckDetails", struct());
root = sixgr.truth.evaluateStrictAnchorStatus(ctx.RunFolder, scfg, cfg, ...
    verdict, table(), table(), struct());

assert(logical(root.Status.ArtifactCompletenessOk), ...
    "A PRACH-only runner must use its component artifact scope.");
assert(~contains(string(root.Status.ResultStatusReason), ...
    "required_artifacts_missing_or_incomplete"), ...
    "Full-LLS plot absence must not contaminate component-run status.");

% The 6GR PDCCH study is also a standalone component runner.  It produces
% physical PDCCH waveform/blind-decode evidence and must never be forced to
% fabricate PDSCH/PUSCH trials, scheduler grants, or configured/effective
% data-channel rows merely to make the root reducer pass.
scfg = sixgr.util.structSet(scfg, ...
    "scenario.runner_profile", "ctrl6gr_pdcch_study");
cfg = sixgr.util.structSet(cfg, ...
    "run.runnerProfile", "ctrl6gr_pdcch_study");
delete(fullfile(ctx.Layout.AirInterfaceCSVDir, "dl_pdsch_trials.csv"));
delete(fullfile(ctx.Layout.AirInterfaceCSVDir, "ul_pusch_trials.csv"));
root = sixgr.truth.evaluateStrictAnchorStatus(ctx.RunFolder, scfg, cfg, ...
    verdict, table(), table(), struct());
assert(root.Status.RunCompleted && root.Status.ArtifactsWritten, ...
    "PDCCH-only execution must retain honest lifecycle and artifact status.");
assert(root.Status.ConfiguredEffectivePolicyOk, ...
    "PDCCH-only execution must not require an unrelated data-channel operating-point table.");
assert(root.Status.PDCCHGrantBindingOk && ...
    root.Status.PDCCHGrantBindingRequiredGrantCount == 0, ...
    "Standalone PDCCH trials must not be reclassified as scheduled PDSCH/PUSCH grant bindings.");
assert(root.Status.ResultOk, ...
    "A complete PDCCH-only component run with no truth failures must pass its applicable root contract.");

ok = true;
end
