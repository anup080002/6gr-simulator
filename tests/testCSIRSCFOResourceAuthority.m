function ok=testCSIRSCFOResourceAuthority()
% A full-band CSI beam sweep is not a repeated observation of one channel.
% Native CSI-RS/OFDM component with no CFO and independently phased beams.
setup6GRSimToolkit('Verbose',false);
carrier=nrCarrierConfig('NSizeGrid',273,'SubcarrierSpacing',30,'NCellID',17,'NSlot',1);
cfg=struct();
cfg.run.strictMode=true;
cfg.channel.model='AWGN';
cfg.phy.csirs=struct('enable',true,'period_slots',5,'offset_slots',1, ...
    'numResources',2,'nPorts',4,'density','one','resourceIDs',[11 29], ...
    'rowNumbers',[4 4],'symbolLocationsByResource',[3 10], ...
    'subcarrierLocationsByResource',[0 0],'rbOffsetsByResource',[0 0], ...
    'numRBsByResource',[273 273],'runtimeChannelEstimator','nr_channel_estimate');
cfg.phy.mimo=struct('strict',true,'measurementMaxAgeSlots',8);
cfg.phy.csi.reportConfiguration=struct('Ports',4);
cfg.phy.rx.cfoCorrectionEnabled=true;
cfg.phy.impairments.cfoEstimationMethod='reference_symbol_phase_slope';
cfg.lls6g.userContext=struct('RuntimeUEIndex',1,'RuntimeCurrentSlot',2);
cfg.lls6g.runtimePowerContext.WaveformAmplitudeUnit='sqrt_mW';
cfg.integration=struct('run_mode','FIXED_SNR_SWEEP','configured_snr_is_link_authority',true);
[~,~,info]=sixgr.phy.refsig.csirs(carrier,cfg);
H=[.8 0 .6 0;0 .6 0 .8];
grid=complex(zeros(12*carrier.NSizeGrid,carrier.SymbolsPerSlot,2));
for n=1:numel(info.Resources)
    reference=info.Resources(n);
    ports=nrResourceGrid(carrier,4);
    ports(reference.Indices)=reference.Symbols;
    received=reshape(reshape(ports,[],4)*H.',size(grid));
    grid=grid+received*exp(1i*.9*(n-1));
end
waveform=nrOFDMModulate(carrier,grid);
searchEnd=37; unknownDelay=13;
capture=[zeros(unknownDelay,2);waveform;zeros(searchEnd-unknownDelay,2)];
rx=sixgr.phy.refsig.receiveCSIRSWaveform( ...
    carrier,cfg,capture,capture,[0 searchEnd],struct());
assert(rx.ReceiveTiming.TimingOffsetSamples==unknownDelay);
assert(~rx.ReceiverTrackingCorrection.CFOEstimateAvailable && ...
    ~rx.ReceiverTrackingCorrection.CFOCorrectionApplied && ...
    isnan(rx.ReceiverTrackingCorrection.EstimatedCFO_Hz), ...
    'sixgr:test:CSIRSBeamPhaseUsedAsCFO', ...
    'Single-symbol resources on different beams do not provide a repeated-channel frequency estimate.');
assert(rx.CSIRSObservation.Observed && rx.CSIRSObservation.ChannelEstimateAvailable && ...
    ~rx.PDSCHDecodeAttempted, ...
    'The missing repeated-frequency observation must not erase actual CSI-RS channel measurements.');
fprintf('CSIRS_CFO_RESOURCE_AUTHORITY_PASS PRB=273 ports=4 resources=2 no_cross_beam_CFO=1\n');
% An independently phased resource is not the same channel observed again.
% Opposite resource phases can cancel in a composite reference waveform
% before magnitude detection. Exercise the actual native CSI-RS generator
% and practical receiver over the wider capture search used by H4. This is
% a declared fixed-channel component, not qualification of a CDL realization.
searchEnd=1229;
for phase=[0 pi]
    oppositeGrid=complex(zeros(size(grid)));
    for n=1:numel(info.Resources)
        reference=info.Resources(n);
        ports=nrResourceGrid(carrier,4);
        ports(reference.Indices)=reference.Symbols;
        mapped=reshape(reshape(ports,[],4)*H.',size(grid));
        oppositeGrid=oppositeGrid+mapped*exp(1i*phase*(n-1));
    end
    oppositeWaveform=nrOFDMModulate(carrier,oppositeGrid,'Windowing',0);
    physical=[zeros(unknownDelay,2);oppositeWaveform;zeros(searchEnd-unknownDelay,2)];
    rate=nrOFDMInfo(carrier).SampleRate;
    rxCFO=400;
    practical=physical.*exp(1i*2*pi*rxCFO*(0:size(physical,1)-1).'/rate);
    cpConfig=cfg;
    cpConfig.phy.impairments.cfoEstimationMethod='cyclic_prefix';
    for cpPolicy=["full_prefix","received_coherence_window"]
    cpConfig.phy.impairments.cfoCPObservation=struct( ...
        'Policy',cpPolicy,'WindowFraction',.5,'FalseAlarmProbability',1e-4);
    measured=sixgr.phy.refsig.receiveCSIRSWaveform( ...
        carrier,cpConfig,practical,physical,[0 searchEnd],struct());
    assert(measured.ReceiveTiming.TimingOffsetSamples==unknownDelay && ...
        measured.PhysicalMeasurementReceiveTiming.TimingOffsetSamples==unknownDelay, ...
        'test:CSIRSResourcePhaseCancelledTiming', ...
        'Resource phase=%g must not change practical timing on either receive plane.',phase);
    assert(measured.ReceiverTrackingCorrection.CFOEstimateAvailable && ...
        measured.PhysicalMeasurementTrackingCorrection.CFOEstimateAvailable && ...
        abs(measured.ReceiverTrackingCorrection.EstimatedCFO_Hz-rxCFO)<1e-6 && ...
        abs(measured.PhysicalMeasurementTrackingCorrection.EstimatedCFO_Hz)<1e-6, ...
        'test:CSIRSResourcePhaseContaminatedCFO', ...
        'Resource-dependent beam phase must not become a CP frequency correction.');
    assert(~measured.ReceiveTiming.OracleTimingUsed && ...
        ~measured.ReceiveTiming.ReceiverZeroPaddingUsed && ...
        measured.ReceiveTiming.TimingSearchHypothesisCount==searchEnd+1);
    assert(measured.ReceiveTiming.ReferenceResourceEvidence.ResourceCount==2 && ...
        measured.ReceiveTiming.InitialTimingOffsetSamples==unknownDelay && ...
        measured.ReceiverTrackingCorrection.InitialReceiveTiming.TimingOffsetSamples==unknownDelay && ...
        measured.ReceiverTrackingCorrection.FrequencyObservationStartSample==unknownDelay && ...
        measured.PhysicalMeasurementTrackingCorrection.FrequencyObservationStartSample==unknownDelay && ...
        measured.ReceiveTiming.TimingReestimatedAfterCFO && ...
        measured.ReceiverTrackingCorrection.EstimateEvidence.ObservationPolicy==cpPolicy && ...
        measured.PhysicalMeasurementTrackingCorrection.EstimateEvidence.ObservationPolicy==cpPolicy, ...
        'Installed CP policy and initial/final receiver timing must survive both receive planes.');
    end
end
fprintf('CSIRS_RESOURCE_TIMING_AUTHORITY_PASS PRB=273 resources=2 wide_search=1230 no_beam_phase_CFO=1\n');
ok=true;
end
