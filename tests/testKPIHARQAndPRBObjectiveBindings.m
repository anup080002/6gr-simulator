function ok = testKPIHARQAndPRBObjectiveBindings()
%TESTKPIHARQANDPRBOBJECTIVEBINDINGS Bind KPI rows to runtime event/resource truth.

setup6GRSimToolkit("Verbose", false);
raw = struct();
raw.UL = localDirectionRows("UL");
raw.DL = localDirectionRows("DL");
raw.HARQTimeline = localHARQTimeline();
raw.ULGrants = localGrantRows("UL", [1; 2], [0; 0], [2; 2], [0; 7], [7; 7]);
raw.DLGrants = localGrantRows("DL", [1; 1; 2], [0; 2; 0], [4; 4; 1], [0; 0; 0], [7; 7; 14]);
raw.SlotTrace = table( ...
    [1; 2], [1; 1], [0; 0], [14; 14], [0; 0], [14; 14], ...
    'VariableNames', {'CanonicalSlot','SweepPointIndex','DLSymbolStart','DLNumSymbols','ULSymbolStart','ULNumSymbols'});
raw.GridNumRBs = 10;
raw.NumResourceCells = 1;
raw.SymbolsPerSlot = 14;
raw.Paths = struct( ...
    "UL", "air_interface/csv/ul_pusch_trials.csv", ...
    "DL", "air_interface/csv/dl_pdsch_trials.csv", ...
    "PacketSDU", "packet_flow/csv/live_packet_sdu_delivery_ledger.csv", ...
    "ApplicationPackets", "packet_flow/csv/live_application_packet_delivery_ledger.csv", ...
    "HARQTimeline", "harq/csv/live_harq_observation_timeline.csv", ...
    "ULGrants", "packet_flow/csv/live_ul_scheduler_grants.csv", ...
    "DLGrants", "packet_flow/csv/live_dl_scheduler_grants.csv", ...
    "SlotTrace", "packet_flow/csv/slot_trace.csv");

out = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw, ...
    "RunId", "run-kpi-1", "ScenarioName", "kpi_event_fixture", ...
    "StrictMode", true, "MeasurementWindowSec", 0.002, ...
    "EffectiveBandwidthHz", 1e6, "SourcePaths", raw.Paths);

expected = struct( ...
    "UL_HARQ_NACK_Rate", 1/3, ...
    "DL_HARQ_NACK_Rate", 1/3, ...
    "UL_Retransmission_Rate", 1/3, ...
    "DL_Retransmission_Rate", 1/3, ...
    "UL_PRB_Utilization", 28/280, ...
    "DL_PRB_Utilization", 56/280);
names = string(fieldnames(expected));
for i = 1:numel(names)
    row = out.ReconstructionSummary(string(out.ReconstructionSummary.KPIName) == names(i), :);
    assert(height(row) == 1 && logical(row.StrictOk), ...
        "KPI %s must be reconstructed from canonical runtime evidence.", names(i));
    assert(abs(double(row.ReconstructionValue) - double(expected.(char(names(i))))) < 1e-12, ...
        "KPI %s has an incorrect runtime-evidence value.", names(i));
    assert(string(row.RunId) == "run-kpi-1", "Every KPI row must carry the authoritative run identity.");
end

binding = out.ObjectiveBinding(ismember(string(out.ObjectiveBinding.KPIName), names), :);
assert(height(binding) == 6 && all(logical(binding.MandatoryInScenarioObjective)), ...
    "HARQ and scheduler utilization rows must be mandatory strict bindings.");
assert(all(logical(binding.RawEvidenceAvailable)) && all(logical(binding.StrictOk)) && ...
    all(string(binding.Status) == "pass"), ...
    "Available HARQ/grant truth must not be classified not_applicable.");

rawMissing = rmfield(raw, "HARQTimeline");
outMissing = sixgr.kpi.reconstructLLSKPISummaryFromRaw(rawMissing, ...
    "RunId", "run-kpi-2", "StrictMode", true, ...
    "MeasurementWindowSec", 0.002, "EffectiveBandwidthHz", 1e6, ...
    "SourcePaths", raw.Paths);
missing = outMissing.ObjectiveBinding(contains(string(outMissing.ObjectiveBinding.KPIName), ["HARQ_NACK","Retransmission"]), :);
assert(all(string(missing.Status) == "fail") && all(~logical(missing.RawEvidenceAvailable)), ...
    "Missing mandatory HARQ evidence must fail closed, not become not_applicable.");

ok = true;
end

function T = localDirectionRows(direction)
T = table( ...
    repmat(string(direction), 2, 1), [1; 1], [true; true], [0; 0], [1000; 1000], ...
    [1000; 1000], [1000; 1000], [1; 2], [1; 2], [0; 1], [0; 0], [0; 0], ...
    [1; 1], [0.001; 0.001], ...
    'VariableNames', {'Direction','Goodput_Mbps','CRCPass','BitErrors','BitsCompared', ...
    'TBSize_bits','GoodBits','Frame','Slot','HARQProcessId','RV','NDI', ...
    'AirInterfaceObservation_ms','SlotDuration_s'});
end

function T = localHARQTimeline()
T = table( ...
    ["UL"; "UL"; "UL"; "DL"; "DL"; "DL"], ...
    [0; 0; 1; 0; 0; 1], [1; 2; 2; 1; 1; 2], ...
    [true; false; true; true; false; true], ...
    [false; true; false; false; true; false], ...
    [0; 2; 0; 0; 2; 0], [1; 1; 1; 1; 1; 1], ...
    'VariableNames', {'Direction','HarqID','Slot','CombinedDecodeOK','IsRetransmission','RV','SweepPointIndex'});
end

function T = localGrantRows(direction, slot, prbStart, prbCount, symbolStart, numSymbols)
n = numel(slot);
T = table( ...
    repmat(string(direction), n, 1), slot, ones(n, 1), ones(n, 1), ...
    prbStart, prbCount, symbolStart, numSymbols, ...
    'VariableNames', {'Direction','Slot','SweepPointIndex','BaseStationID', ...
    'PRBStart','PRBCount','SymbolStart','NumSymbols'});
end
