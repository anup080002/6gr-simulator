function ok = testPDSCHRateMatchPatternIntegration()
%TESTPDSCHRATEMATCHPATTERNINTEGRATION Bind exact rate matching to G.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
allocation = 0:167;
emptySources = struct("RateMatchPattern", zeros(1, 0));
patternSources = struct("RateMatchPattern", [0:11 60:71]);
baselineMap = sixgr.pdsch.PDSCHResourceOwnershipMap( ...
    allocation, emptySources);
patternMap = sixgr.pdsch.PDSCHResourceOwnershipMap( ...
    allocation, patternSources);
context = localContext();
baseline = sixgr.pdsch.PDSCHResourcePlan(baselineMap, context);
resolved = sixgr.pdsch.PDSCHResourcePlan(patternMap, context);

assert(numel(patternMap.ReservedUnionIndices) == 24 && ...
    all(patternMap.Entries.ResolvedStatus(1:12) == ...
        "reserved_rate_match_pattern"), ...
    "Rate-match-pattern ownership was not materialized exactly.");
assert(baseline.ExactDataRECount - resolved.ExactDataRECount == 24, ...
    "Rate-match pattern did not remove exactly its union RE count.");
assert(baseline.GPerCodeword - resolved.GPerCodeword == 24 * 6, ...
    "Exact G did not consume the final rate-matched data map.");
assert(sum(resolved.EPerCodeBlock{1}) == resolved.GPerCodeword, ...
    "Per-block E does not sum to rate-match-pattern-aware G.");
ok = true;
end

function context = localContext()
context = struct( ...
    "PRBSet", 0, "SymbolAllocation", [0 14], ...
    "GridNumPRB", 1, ...
    "GridSymbolsPerSlot",14,"BWPStartPRB",0,"AbsoluteSlot",0, ...
    "UnavailableIndices",zeros(1,0), ...
    "DMRSIndicesPerPort", {cell(1, 0)}, ...
    "PTRSIndicesPerPort", {cell(1, 0)}, ...
    "DMRSLogicalPortSet",zeros(1,0), ...
    "PTRSLogicalPortSet",zeros(1,0), ...
    "LayerCountPerCodeword", 1, ...
    "QmPerCodeword", 6, ...
    "CodeBlockCountPerCodeword", 2);
end
