function report = testAll(varargin)
%TESTALL Run full regression test suite.
% Supports focused subsets via `testAll("Names", ["testLLS_DL","testLLS_UL"])`
% and prints per-test durations plus a slowest-tests summary.

p = inputParser;
p.addParameter("Names", strings(0,1), @(x) isstring(x) || ischar(x) || iscellstr(x));
p.addParameter("Verbose", true, @(x) islogical(x) || isnumeric(x));
p.addParameter("ShowSlowest", 10, @(x) isnumeric(x) && isscalar(x) && x >= 0);
p.parse(varargin{:});
opt = p.Results;

setup6GRSimToolkit("Verbose", logical(opt.Verbose));

