    @test6GCSIReportingCoverage, ...
    @test6GReferenceSignalChainCoverage, ...
    @testCSIRuntimeExecution, ...
    @testCSIPayloadPackingRuntime, ...
    @testTRSReferenceSignalExecution, ...
    @test6GMandatoryStudyPackScenarios, ...
    @test6GExactScenarioSuites, ...
    @test6GScenarioRunner, ...
    @test6GScenarioMatrixRunner, ...
    @testLLSDeploymentTopologyConfigWiring, ...
    @test6GLLSMultiUserBeamforming, ...
    @test6GLLSCoupledTruthBidirectional, ...
    @testLLSCoupledTruthFallbackFeedbackSanity, ...
    @test6GAIBenchmarkReporting, ...
    @test6GAIUseCaseCoverage, ...
    @testPresetHygiene, ...
    @testMIBSIB1Recovery, ...
    @testLLS_DL, ...
    @testPDSCHSISORegression, ...
    @testPDSCHMultiPortPrecoding, ...
    @testPMIPrecodingRuntime, ...
    @testLLSClosedLoopLinkAdaptation, ...
    @testLLSHARQGrantReplayTBConsistency, ...
    @testLLSCoupledTruthHARQRoundTrip, ...
    @testNRCQITableAndGrantSizing, ...
    @testChannelEstimationValidation, ...
    @testChannelFactoryCDLAntennaArray, ...
    @testLLSChannelArrayTruthStatus, ...
    @testFadingLinkDelayAlignment, ...
    @testLLSResultRichness, ...
    @testLLSEffectiveOperatingPointSummary, ...
    @testLLSReportBundle, ...
    @testLLSAvailabilityAggregation, ...
