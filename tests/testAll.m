function report = testAll()
%TESTALL Run full regression test suite.

setup6GRSimToolkit("Verbose", true);

tests = { ...
    @testConfig, ...
    @testMIBSIB1Recovery, ...
    @testLLS_DL, ...
    @testLLS_UL, ...
    @testLLS_ReferencePoints, ...
    @testControlDetectionThresholds, ...
    @testLinkExportPipeline, ...
    @testSLS_Abstract, ...
    @testMobilityControlLoop, ...
    @testStrictProxyGuards, ...
    @testStrictMode_NoFallbackAnywhere, ...
    @testHybrid, ...
    @testHybrid_CalibrationCoverage, ...
    @testE2E_FastVsTruth, ...
    @testE2E_TruthPacketSemanticCampaign, ...
    @testSchedulerGrantConsistency, ...
    @testArtifactIntegrity, ...
    @testOrganizeRunResults_E2EArtifactPreservation, ...
    @testAttachProcedure, ...
    @testPDCP_SecurityProfiles, ...
    @testPDCP_RLC_PacketConservation ...
    };

report = struct();
report.ok = true;
report.results = struct([]);

for k = 1:numel(tests)
    fn = tests{k};
    name = func2str(fn);
    r = struct("name", name, "ok", false, "msg", "");
    try
        feval(fn);
        r.ok = true;
    catch ME
        r.ok = false;
        r.msg = ME.message;
        report.ok = false;
    end
    report.results = [report.results; r]; %#ok<AGROW>
    fprintf("[%s] %s\n", ternary(r.ok, "PASS", "FAIL"), name);
    if ~r.ok
        fprintf("       %s\n", r.msg);
    end
end
end

function y = ternary(cond, a, b)
if cond, y = a; else, y = b; end
end
