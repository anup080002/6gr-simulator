allNames = string(cellfun(@func2str, tests, 'UniformOutput', false));
excludedNames = localNormalizeNames(opt.ExcludeNames);
if ~isempty(excludedNames)
    keep = ~ismember(allNames,excludedNames);
    tests = tests(keep);
    allNames = allNames(keep);
end

report = struct();
report.ok = true;
report.results = struct([]);
report.selected_tests = cellstr(allNames);
report.total_duration_s = NaN;

suiteStart = tic;

for k = 1:numel(tests)
    fn = tests{k};
    name = func2str(fn);
    r = struct("name", name, "ok", false, "msg", "", "duration_s", NaN, ...
        "identifier", "", "extended_report_available", false, "diagnostic_rendering_error", "");
    testStart = tic;
    fprintf("FULLSTACK_TEST_START %s\n", name);
    try
        executeRegressionTest(fn);
        r.ok = true;
    catch ME
        r.ok = false;
        r.msg = ME.message;
        report.ok = false;
        r.identifier = ME.identifier;
        [diagnosticText,diagnostic] = sixgr.util.formatExceptionDiagnostic(ME);
        r.extended_report_available = diagnostic.ExtendedReportAvailable;
        r.diagnostic_rendering_error = diagnostic.RenderingErrorIdentifier;
        fprintf(2,'TEST_FAILURE identifier=%s extended_report=%d rendering_error=%s\n%s\n', ...
            r.identifier,r.extended_report_available,r.diagnostic_rendering_error,diagnosticText);
    end
    r.duration_s = toc(testStart);
    report.results = [report.results; r]; %#ok<AGROW>
    fprintf("FULLSTACK_TEST_END %s %s\n", name, ...
        ternary(r.ok, "PASS", "FAIL"));
    fprintf("[%s] %s (%.2fs)\n", ternary(r.ok, "PASS", "FAIL"), name, r.duration_s);
    if ~r.ok
        fprintf("       %s\n", r.msg);
    end
end

report.total_duration_s = toc(suiteStart);
localPrintSlowest(report.results, double(opt.ShowSlowest));
if nargout == 0 && ~report.ok
    error('sixgr:tests:RegressionFailed', 'One or more full-suite regressions failed; see per-test diagnostics.');
end
end

function y = ternary(cond, a, b)
if cond, y = a; else, y = b; end
end

function localEnsureSetup(verbose)
testDir = fileparts(mfilename("fullpath"));
rootDir = fileparts(testDir);
repoReady = localPathContains(rootDir);
testsReady = localPathContains(testDir) && exist("raStrictAnchorConfig", "file") == 2;
if ~(repoReady && testsReady)
    setup6GRSimToolkit("Verbose", logical(verbose));
end
end

function tf = localPathContains(folder)
folder = char(string(folder));
parts = strsplit(path, pathsep);
if ispc
    tf = any(strcmpi(parts, folder));
else
    tf = any(strcmp(parts, folder));
end
end

function names = localNormalizeNames(rawNames)
if ischar(rawNames)
    names = string({rawNames});
elseif iscellstr(rawNames)
    names = string(rawNames);
else
    names = string(rawNames);
end
names = strtrim(names(:));
names = names(strlength(names) > 0);
end

function localPrintSlowest(results, showSlowest)
if isempty(results) || showSlowest <= 0
    return;
end
durations = [results.duration_s];
[sortedDurations, order] = sort(durations, 'descend');
n = min(numel(order), showSlowest);
fprintf("Slowest %d test(s):\n", n);
for i = 1:n
    idx = order(i);
    fprintf("  %2d. %s (%.2fs)\n", i, results(idx).name, sortedDurations(i));
end
end
