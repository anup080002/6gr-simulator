end

function cfg = localProductionSwitchContext()
cfg = withCanonicalSchedulerTiming(sixgr.config.defaultConfig());
nrb = double(sixgr.util.structGet(cfg, "phy.carrier.NSizeGrid", 273));
cfg.phy.bwp.dl = [ ...
    localRuntimeBWP(0, "DL", true, 0, 0, nrb); ...
    localRuntimeBWP(1, "DL", false, 1, 1, nrb)];
cfg.phy.bwp.ul = localRuntimeBWP(0, "UL", true, 1, 0, nrb);
if isfield(cfg.phy, "frameStructure")
    cfg.phy = rmfield(cfg.phy, "frameStructure");
end
if isfield(cfg.phy, "frame")
    cfg.phy = rmfield(cfg.phy, "frame");
end
cfg = sixgr.phy.frame.FrameRuntimeStateBuilder.attachTimingContext(cfg);
[snapshot, carriers] = ...
    sixgr.phy.frame.FrameRuntimeStateBuilder.build(cfg);
carrier = carriers{1};
dlInitial = carrier.configuredBWP(0, "DL");
activation = sixgr.phy.frame.AbsoluteTime.fromAbsoluteSlotSymbol( ...
    2, 0, dlInitial);
queued = carrier.BWPState.scheduleSwitch("DL", 1, activation, ...
    "IssuedTime", sixgr.phy.frame.AbsoluteTime.fromTicks(0), ...
    "ControlBWPID", 0, "TriggerSource", "RRC", ...
    "CommandID", "production-waveform-bwp-switch");
assert(queued.Accepted);
carrier.BWPState.applyUntil(activation);

runtimeState = snapshot.BWPState(1);
runtimeState.ActiveDLBWPID = 1;
runtimeState.ActiveULBWPID = 0;
runtimeState.Epoch = double(carrier.BWPState.Epoch);
runtimeState.CurrentTick = carrier.BWPState.CurrentTime.tickValue();
runtimeState.PendingCommands = ...
    table2struct(carrier.BWPState.pendingTable());
runtimeState.History = table2struct(carrier.BWPState.historyTable());
snapshot.BWPState(1) = runtimeState;
snapshot.DefaultIdentity.SourceBWPID = 1;
snapshot.DefaultIdentity.DLBWPID = 1;
snapshot.DefaultIdentity.ULBWPID = 0;
cfg.phy.frameStructure.TimingContext = snapshot;
end

