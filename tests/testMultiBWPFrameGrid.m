function localAssertError(fcn, expectedIdentifier)
try
    fcn();
catch cause
    assert(string(cause.identifier) == string(expectedIdentifier), ...
        "Expected '%s'; received '%s': %s", ...
        expectedIdentifier, cause.identifier, cause.message);
    return;
end
error("sixgr:tests:ExpectedErrorNotRaised", ...
    "Expected error '%s' was not raised.", expectedIdentifier);
end
