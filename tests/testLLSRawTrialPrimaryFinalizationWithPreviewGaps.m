function ok = testLLSRawTrialPrimaryFinalizationWithPreviewGaps()
%TESTLLSRAWTRIALPRIMARYFINALIZATIONWITHPREVIEWGAPS Finalize rows on primary truth only.

setup6GRSimToolkit("Verbose", false);

T = table( ...
    ["DL"; "UL"], [1; 1], [2; 2], [1; 0], [1024; 1024], [12.5; 0], ...
    [24; 16], [10; 8], ["16QAM"; "QPSK"], [0.50; 0.30], ...
    [NaN; NaN], ["geometry_preview"; "geometry_preview"], [NaN; NaN], ...
    [50; NaN], [NaN; NaN], [NaN; NaN], ...
    [true; false], [2; NaN], [NaN; NaN], [false; false], ...
    'VariableNames', { ...
    'Direction','Frame','Slot','CRCPass','BitsCompared','Goodput_Mbps', ...
    'AllocatedPRBCount','MCSIndex','Modulation','TargetCodeRate', ...
    'LargeScaleSINR_dB','LargeScaleSINRSource','PRBStart', ...
    'EstimatedCFO_PreCorrection_Hz','EstimatedCFO_Hz','CFOError_Hz', ...
    'TimingEstimateUsed','EstimatedTimingOffset_PreCorrection_samples','TimingError_samples','Crash'});

T = sixgr.util.applyLLSRawTrialLifecycle(T);

assert(all(logical(T.FinalizedFlag)), ...
    "Raw trial rows with complete primary truth must finalize even when secondary preview fields are missing.");
assert(~any(logical(T.PartialRowFlag)), ...
    "Secondary preview gaps must not mark otherwise complete raw trial rows as partial.");
assert(all(strcmpi(string(T.RowLifecycleState), "finalized")), ...
    "RowLifecycleState must remain finalized when only preview/secondary fields are absent.");
assert(all(strcmpi(string(T.PrimaryTruthValueStatus), "OK")), ...
    "PrimaryTruthValueStatus must stay OK when decode/grant fields are present.");
assert(all(logical(T.SecondaryFieldGapFlag)) && all(double(T.SecondaryFieldGapCount) >= 1), ...
    "Secondary preview gaps must be retained in SecondaryFieldGap* columns.");
assert(all(contains(string(T.SecondaryFieldGapReason), "large_scale_sinr_not_finalized")), ...
    "Missing preview SINR must be represented as field-level large_scale_sinr_not_finalized.");
assert(all(strcmpi(string(T.LargeScaleSINRValueStatus), "NOT_AVAILABLE")), ...
    "Preview SINR gaps must be field-level NOT_AVAILABLE, not row-level partial truth.");
assert(all(strlength(string(T.NAReason)) == 0), ...
    "Finalized rows must not carry row-level NAReason for preview-only gaps.");

ok = true;
end
