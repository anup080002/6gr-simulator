function ok = testLLSStageTraceEvidence()
%TESTLLSSTAGETRACEEVIDENCE Verify direct DL/UL stage evidence export from active raw trials.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
cfg.run.numFrames = 1;
cfg.channel.snr_dB = 10;
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.run.noiseOperatingMode = "configured_snr_anchor_after_large_scale_gain";
cfg.run.interferenceExecutionMode = "none";
multiUser = struct("Enabled", true, "NumUsers", 1, "RNTIStart", 320, "ExecutionModel", "slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize(cfg, fullfile(tmp, "runtime"), multiUser, struct(), 1);
state.CurrentServingIdx(1) = 1;
state.CurrentServingMetric_dBm(1) = -70;
state.CurrentSlot = 1;
state.CurrentFrame = 1;
state.CurrentSNR_dB = 10;
state.LargeScaleState.BeamIndex(1,1) = 1;
state.LargeScaleState.BeamGain_dB(1,1) = 0;
state.LargeScaleState.RxPower_dBm(1,1) = -70;
state.LargeScaleState.BasePathloss_dB(1,1) = 100;
state.LargeScaleState.Pathloss_dB(1,1) = 100;
state.LargeScaleState.Shadow_dB(1,1) = 0;
state.LargeScaleState.O2I_dB(1,1) = 0;
[cfgDL, state] = sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg, state, 1, "DL");
[cfgUL, state] = sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg, state, 1, "UL");

grant = struct( ...
    "UEIndex", 1, ...
    "RNTI", 320, ...
    "ServingCell", 1, ...
    "CQIUsed", 7, ...
    "RIUsed", 1, ...
    "PMI", 0, ...
    "CRI", 0, ...
    "MCSTable", "qam64_table1", ...
    "CQITable", "table1", ...
    "AMCMode", "cqi_driven", ...
    "GrantReason", "stage_trace_unit_test", ...
    "Frame", 1, ...
    "Slot", 1, ...
    "HARQ", struct(), ...
    "PBCHGatingActive", true, ...
    "PRACHGatingActive", true, ...
    "PDCCHGatingActive", true, ...
    "SRSGatingActive", true, ...
    "ControlEligible", true, ...
    "ControlDecodeOk", true, ...
    "GrantControlState", "control_ok", ...
    "CellAcquisitionState", "acquired", ...
    "AccessState", "succeeded", ...
    "SRSValidityState", "valid", ...
    "CSIValidityState", "fresh_runtime_srs", ...
    "SRSValid", true, ...
    "SRSAgeSlots", 0);

dl = sixgr.link.runDLPDSCHThroughput(cfgDL, ...
    "NumFrames", 1, ...
    "SNR_dB", 10, ...
    "GrantSnapshot", grant, ...
    "InterferenceBundle", struct([]));
ul = sixgr.link.runULPUSCHThroughput(cfgUL, ...
    "NumFrames", 1, ...
    "SNR_dB", 10, ...
    "GrantSnapshot", grant, ...
    "InterferenceBundle", struct([]));

trialT = [dl.TrialTable; ul.TrialTable]; %#ok<AGROW>
artifacts = sixgr.truth.exportLLSLiveSignalChainTables(fullfile(tmp, "run"), trialT, table(), struct());
stageT = readtable(char(artifacts.StageTracePath), "VariableNamingRule", "preserve");

requiredVars = { ...
    'TxChainKernel','RxChainKernel','RawTrialTraceSource','StageEvidenceSource', ...
    'TBCRCLength_bits','NumCodeBlocks','RateMatchedBits','DataRECount','DMRSRECount','PTRSRECount', ...
    'TimingEstimateUsed','NMSE_dB','DecoderIterations','InterferenceContributorCount','GrantControlState','ControlDecodeOk', ...
    'ConfiguredBeamSelectionStrategy','PrecoderSource','PrecodingMode','PrecodingApplicationStage','PrecodingActive', ...
    'ExplicitBeamWeightsApplied','TransformPrecodingApplied','BeamformingApplied','AppliedBeamIndexSet', ...
    'AppliedPrecoderPMI','AppliedPrecoderPMIType','AppliedPrecoderCodebookMode','RequestedVsAppliedPrecoderPMIMatchStatus','PrecodingNumPorts','PrecodingNumLayers', ...
    'RequestedBeamIndexSet','RequestedPrecoderPMI','RequestedPrecoderSource','AppliedPrecoderSource', ...
    'MCSAuthority','ModulationAuthority','GrantOperatingPointSource','AppliedOperatingPointSource', ...
    'CFOEstimateAvailability','CFOErrorDefinition','CFOValueStatus','TimingEstimateAvailability','TimingErrorDefinition','TimingValueStatus', ...
    'LargeScaleSINRValueStatus','LargeScaleSINRFinalizedFlag','LargeScaleSINRNAReason','PRBStart','AllocatedPRBCount', ...
    'RunUUID','RunTag','ScenarioID','RunnerProfile','ConfigHash','SourceArtifact','SourceTable','ArtifactClass','SemanticState', ...
    'CountsTowardCoverage','MachineReadable','HumanReadable','RowLifecycleState','PartialRowFlag','FinalizedFlag','FallbackFlag','PlaceholderFlag','NAReason', ...
    'BSAntennaArrayClass','BSAntennaArrayType','BSAntennaElements','UEAntennaArrayClass','UEAntennaArrayType','UEAntennaElements', ...
    'AntennaRuntimeObjectCreated','ChannelArrayModel','ChannelUsesCountOnlyAntennaModel', ...
    'PropagationDistance_m','GeometricPropagationDelay_s','ToD_s','ToA_s','ToAEstimate_s','ChannelDelaySource','AntennaGeometrySource','SameFlowEvidenceSource', ...
    'GrantContextId','GrantWorkerSafe','GrantSharedStateCommitMode'};
assert(all(ismember(requiredVars, stageT.Properties.VariableNames)), ...
    "Stage trace must expose direct coding, mapping, receiver, control, and interference provenance.");
assert(height(stageT) == 2, ...
    "Stage trace export must preserve both DL and UL runtime rows.");

dlMask = strcmpi(string(stageT.Direction), "DL");
ulMask = strcmpi(string(stageT.Direction), "UL");
assert(any(dlMask) && any(ulMask), ...
    "Stage trace must preserve both DL and UL directions.");
assert(any(strcmpi(string(stageT.TxChainKernel(dlMask)), "sixgr.phy.dl.PDSCH_Tx")) && ...
    any(strcmpi(string(stageT.RxChainKernel(dlMask)), "sixgr.phy.dl.PDSCH_Rx")), ...
    "DL stage trace rows must identify the active PDSCH Tx/Rx kernels.");
assert(any(strcmpi(string(stageT.TxChainKernel(ulMask)), "sixgr.phy.ul.PUSCH_Tx")) && ...
    any(strcmpi(string(stageT.RxChainKernel(ulMask)), "sixgr.phy.ul.PUSCH_Rx")), ...
    "UL stage trace rows must identify the active PUSCH Tx/Rx kernels.");
assert(any(strcmpi(string(stageT.RawTrialTraceSource(dlMask)), "air_interface/csv/dl_pdsch_trials.csv")) && ...
    any(strcmpi(string(stageT.RawTrialTraceSource(ulMask)), "air_interface/csv/ul_pusch_trials.csv")), ...
    "Stage trace rows must disclose the raw runtime artifact they were derived from.");
assert(all(strcmpi(string(stageT.GrantControlState), "control_ok")), ...
    "Stage trace must preserve the runtime grant-control state.");
assert(any(logical(stageT.PrecodingActive(dlMask)) & logical(stageT.ExplicitBeamWeightsApplied(dlMask)) & logical(stageT.BeamformingApplied(dlMask))), ...
    "DL stage trace must directly expose the applied explicit precoder path.");
assert(all(strlength(string(stageT.AppliedBeamIndexSet(dlMask))) > 0) && ...
    all(isfinite(double(stageT.AppliedPrecoderPMI(dlMask)))) && ...
    all(strlength(string(stageT.AppliedPrecoderPMIType(dlMask))) > 0), ...
    "DL stage trace must export the actually applied beam index set and PMI truthfully.");
assert(all(~logical(stageT.ExplicitBeamWeightsApplied(ulMask))), ...
    "UL stage trace must not overclaim explicit beam-weight application.");
assert(all(strcmpi(string(stageT.PrecodingMode(ulMask)), "ul_codebook_tpmi")) && ...
    all(strcmpi(string(stageT.PrecoderSource(ulMask)), "ul_pusch_native_codebook_tpmi")) && ...
    all(logical(stageT.BeamformingApplied(ulMask))) && ...
    all(isfinite(double(stageT.AppliedPrecoderPMI(ulMask)))) && ...
    all(strcmpi(string(stageT.RequestedVsAppliedPrecoderPMIMatchStatus(ulMask)), "requested_matches_runtime_applied")), ...
    "UL stage trace must expose runtime-applied native PUSCH TPMI instead of the old scheduler-only PMI reference.");
assert(all(strcmpi(string(stageT.MCSAuthority), "scheduler_grant")) && ...
    all(strcmpi(string(stageT.ModulationAuthority), "scheduler_grant")), ...
    "Stage trace must preserve operating-point authority from the raw runtime grants.");
assert(all(strcmpi(string(stageT.CFOEstimateAvailability), "missing")) && ...
    all(strcmpi(string(stageT.CFOValueStatus), "NOT_AVAILABLE")) && ...
    all(~isfinite(double(stageT.CFOError_Hz))), ...
    "Stage trace must preserve missing-estimate CFO lineage instead of fake finalized errors.");
assert(all(isfinite(double(stageT.AllocatedPRBCount))) && all(isfinite(double(stageT.PRBStart))), ...
    "Stage trace must preserve actual PRB start/count linkage from the raw runtime grants.");
assert(all(logical(stageT.AntennaRuntimeObjectCreated)) && ...
    all(strlength(string(stageT.ChannelArrayModel)) > 0) && ...
    all(isfinite(double(stageT.ToD_s))) && all(isfinite(double(stageT.ToA_s))) && ...
    all(double(stageT.ToA_s) >= double(stageT.ToD_s)), ...
    "Stage trace must preserve same-flow antenna-object and ToD/ToA evidence.");
assert(all(strlength(string(stageT.GrantContextId)) > 0), ...
    "Stage trace must preserve stable grant context identifiers for future worker-safe verification.");
assert(all(logical(stageT.GrantWorkerSafe)) && all(strcmpi(string(stageT.GrantSharedStateCommitMode), "serial_coordinator_commit")), ...
    "Stage trace must disclose the worker-safe grant-commit contract.");

ok = true;
end
