function ok = testFRCReferencePointStatisticalQualification()
%TESTFRCREFERENCEPOINTSTATISTICALQUALIFICATION One-sided FRC sample gate.

assert(sixgr.conformance.referencePointStatisticallyQualified( ...
    10000, true, 9604), ...
    ["A completed prespecified FRC sample is statistically eligible; " ...
    "the separate one-sided confidence bound decides pass/fail."]);
assert(~sixgr.conformance.referencePointStatisticallyQualified( ...
    9603, true, 9604), ...
    "A sample below the prespecified floor must remain unqualified.");
assert(~sixgr.conformance.referencePointStatisticallyQualified( ...
    10000, false, 9604), ...
    "A diagnostic or underspecified plan must remain unqualified.");
assert(~sixgr.conformance.referencePointStatisticallyQualified( ...
    2, false, NaN), ...
    "An ineligible diagnostic plan may carry no production sample floor.");
ok = true;
end
