function ok = test6G4GHzSystemLevelCanonicalArtifacts()
%TEST6G4GHZSYSTEMLEVELCANONICALARTIFACTS Verify canonical browser-owned artifacts from the system-level LLS runner.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

basePath = fullfile(pwd, "simulator", "configs", "scenarios", "variants", "SCN00_BASELINE_CAPACITY.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(basePath);
s = scfg.toStruct();

s.meta.scenario_id = "SCN00_BASELINE_CAPACITY_SYSTEMLEVEL_SMOKE";
s.meta.description = "Bounded system-level LLS canonical artifact smoke for the 4 GHz family.";
s.meta.scenario_name = s.meta.description;
s.run_control.study_mode = "smoke";
s.run_control.num_seeds = 1;
s.run_control.num_drops = 1;
s.run_control.warmup_time_ms = 0;
s.run_control.measurement_time_ms = 1;
s.run_control.total_time_ms = 1;
s.run_control.num_workers = 1;
s.output.backend = "filesystem";
s.output.profile = "SCN00_BASELINE_CAPACITY_SYSTEMLEVEL_SMOKE";
s.output.save_figures = false;
s.output.save_png = false;
s.output.save_mat = false;
s.simulation.n_frames = 1;
s.simulation.n_slots = 2;
s.simulation.n_subframes = 1;
s.simulation.monte_carlo_iterations = 1;
s.scenario.bundle_anchor_cases = {"ul_lowpapr"};

scenarioPath = fullfile(tmp, "SCN00_BASELINE_CAPACITY_SYSTEMLEVEL_SMOKE.yaml");
sixgr.lls6g.config.writeYAML(scenarioPath, s);

out = run_6g_phy_lls_single(scenarioPath, tmp, "system_level_smoke");
assert(out.Ok, "Bounded system-level LLS scenario smoke should complete.");

runFolder = char(string(out.RunFolder));
requiredFiles = { ...
    fullfile(runFolder, "reports", "csv", "runtime_operating_mode.csv"), ...
    fullfile(runFolder, "reports", "csv", "deployment_layout_reference.csv"), ...
    fullfile(runFolder, "reports", "csv", "live_control_gating_summary.csv"), ...
    fullfile(runFolder, "reports", "csv", "live_stage_status.csv"), ...
    fullfile(runFolder, "reports", "csv", "live_channel_state_tti.csv"), ...
    fullfile(runFolder, "reports", "csv", "live_rsrp_serving_trace.csv"), ...
    fullfile(runFolder, "packet_flow", "csv", "live_dl_scheduler_grants.csv"), ...
    fullfile(runFolder, "packet_flow", "csv", "live_ul_scheduler_grants.csv"), ...
    fullfile(runFolder, "air_interface", "csv", "dl_pdsch_trials.csv"), ...
    fullfile(runFolder, "air_interface", "csv", "ul_pusch_trials.csv"), ...
    fullfile(runFolder, "air_interface", "csv", "multiuser_user_summary.csv")};
for i = 1:numel(requiredFiles)
    assert(exist(requiredFiles{i}, "file") == 2, "Missing canonical system-level artifact: %s", requiredFiles{i});
end

runtimeT = localReadCanonicalTable(fullfile(runFolder, "reports", "csv", "runtime_operating_mode.csv"));
assert(any(strcmpi(string(runtimeT.Direction), "DL")), "Runtime operating mode must expose a DL row.");
assert(any(strcmpi(string(runtimeT.Direction), "UL")), "Runtime operating mode must expose a UL row.");
assert(all(strcmpi(string(runtimeT.ControlIntegrationMode), "system_level_scheduler_waveform_phy_no_coupled_signal_gating")), ...
    "Baseline runtime operating mode must disclose the waveform PHY control integration boundary honestly.");
assert(all(strcmpi(string(runtimeT.CoupledGrantExecutionMode), "system_level_scheduler_with_grant_waveform_replay")), ...
    "Baseline runtime operating mode must disclose waveform grant replay execution honestly.");
assert(all(strcmpi(string(runtimeT.ExecutionBackend), "WAVEFORM_SYSTEM_PHY")), ...
    "Baseline runtime operating mode must disclose the waveform system PHY backend.");
assert(all(strcmpi(string(runtimeT.PHYMode), "GRANT_CRC_WAVEFORM_REPLAY_EXPERIMENTAL")), ...
    "Baseline runtime operating mode must disclose the waveform replay PHY mode.");
assert(all(logical(runtimeT.WaveformBacked)), ...
    "Baseline runtime operating mode must be waveform-backed.");
assert(ismember("WaveformPHYActive", string(runtimeT.Properties.VariableNames)), ...
    "Runtime operating mode must expose WaveformPHYActive proof.");
assert(ismember("ProxyPHYActive", string(runtimeT.Properties.VariableNames)), ...
    "Runtime operating mode must expose ProxyPHYActive proof.");
assert(ismember("FallbackUsed", string(runtimeT.Properties.VariableNames)), ...
    "Runtime operating mode must expose FallbackUsed proof.");
assert(all(logical(runtimeT.WaveformPHYActive)), ...
    "Baseline runtime operating mode must mark waveform PHY active.");
assert(~any(logical(runtimeT.ProxyPHYActive)), ...
    "Baseline runtime operating mode must not mark proxy PHY active.");
assert(~any(logical(runtimeT.FallbackUsed)), ...
    "Baseline runtime operating mode must not mark fallback usage.");
assert(all(strcmpi(string(runtimeT.SystemLevelSINRValueStatus), "available_system_level_estimate")), ...
    "Runtime operating mode must disclose that system-level SINR is an available estimate, not receiver Hest or decoder truth.");
assert(all(strcmpi(string(runtimeT.ReceiverHestSINRValueStatus), "OK")), ...
    "Runtime operating mode must disclose receiver-Hest SINR from actual waveform replay.");
assert(all(strcmpi(string(runtimeT.DecoderTruthProxySINRValueStatus), "unavailable")), ...
    "Runtime operating mode must not promote EVM-derived proxy SINR as decoder-truth evidence.");
assert(all(strcmpi(string(runtimeT.ExplicitPrecoderReplayStatus), "materialized")), ...
    "Runtime operating mode must disclose per-grant waveform precoder replay evidence as materialized.");
assert(all(strcmpi(string(runtimeT.ChannelArrayValueStatus), "approximate_system_context")), ...
    "Runtime operating mode must disclose system-level channel-array handling as approximate context.");

layoutT = localReadCanonicalTable(fullfile(runFolder, "reports", "csv", "deployment_layout_reference.csv"));
assert(height(layoutT) == 1, "Deployment layout reference must contain a single summary row.");
assert(double(layoutT.NumSites(1)) == 19, "Deployment layout reference must preserve the 19-site baseline.");
assert(double(layoutT.SectorsPerSite(1)) == 3, "Deployment layout reference must preserve 3 sectors per site.");
assert(double(layoutT.NumCells(1)) == 57, "Deployment layout reference must preserve the 57-cell baseline.");
assert(double(layoutT.NumUEs(1)) == 100, "Deployment layout reference must preserve the 100-UE baseline.");

dlT = localReadCanonicalTable(fullfile(runFolder, "air_interface", "csv", "dl_pdsch_trials.csv"));
ulT = localReadCanonicalTable(fullfile(runFolder, "air_interface", "csv", "ul_pusch_trials.csv"));
assert(~isempty(dlT) || ~isempty(ulT), "System-level smoke must publish at least one canonical raw trial row.");
if ~isempty(dlT)
    assert(all(strcmpi(string(dlT.BeamSelectionStrategy), "runtime_best_beam_per_link")), ...
        "DL raw trials must preserve the runtime-best-beam baseline truth.");
    assert(all(strcmpi(string(dlT.ActualMCSSelectionMode), "scheduler_grant")), ...
        "DL raw trials must disclose scheduler grants as the applied operating-point source.");
    assert(all(isfinite(double(dlT.AppliedAWGNSNR_dB))), ...
        "Baseline DL raw trials must publish the grant-level waveform replay AWGN SNR.");
    assert(all(strcmpi(string(dlT.AppliedAWGNSNRSource), "grant_level_waveform_replay_awgn_snr")), ...
        "Baseline DL raw trials must label applied AWGN SNR as waveform replay evidence.");
    assert(all(isfinite(double(dlT.SystemLevelSINR_dB))), ...
        "Baseline DL raw trials must publish the system-level desired/interference/noise SINR estimate separately.");
    assert(all(strcmpi(string(dlT.SystemLevelSINRValueRole), "runtime_state_derived")), ...
        "Baseline DL raw trials must classify the system-level SINR as runtime-state-derived.");
    assert(all(isfinite(double(dlT.ReceiverHestSINR_dB))), ...
        "System-level DL raw trials must publish receiver-Hest SINR from waveform replay.");
    assert(all(strcmpi(string(dlT.ReceiverHestSINRSource), "receiver_hest_reference_signal_measurement")), ...
        "System-level DL raw trials must source receiver-Hest SINR from receiver Hest/CSI feedback.");
    assert(all(strcmpi(string(dlT.ReceiverHestSINRValueStatus), "OK")), ...
        "System-level DL raw trials must label receiver-Hest SINR as available replay evidence.");
    assert(all(~isfinite(double(dlT.DecoderTruthProxySINR_dB))), ...
        "System-level DL raw trials must not publish EVM-derived decoder-truth SINR.");
    assert(all(contains(lower(string(dlT.DecoderTruthProxySINRSource)), "not_decoder_truth") | ...
        contains(lower(string(dlT.DecoderTruthProxySINRSource)), "not_materialized")), ...
        "System-level DL raw trials must disclose decoder SINR proxy quarantine/unavailability.");
    assert(all(strcmpi(string(dlT.DecoderTruthProxySINRValueStatus), "unavailable")), ...
        "System-level DL raw trials must keep decoder-side EVM SINR proxy unavailable in primary truth.");
    assert(all(strcmpi(string(dlT.ExplicitPrecoderReplayStatus), "materialized")), ...
        "System-level DL raw trials must label per-grant precoder replay evidence as materialized.");
    assert(all(strcmpi(string(dlT.ChannelArrayValueStatus), "approximate_system_context")), ...
        "System-level DL raw trials must label channel-array handling as approximate system context.");
end
if ~isempty(ulT)
    assert(all(strcmpi(string(ulT.BeamSelectionStrategy), "runtime_best_beam_per_link")), ...
        "UL raw trials must preserve the runtime-best-beam baseline truth.");
    assert(all(strcmpi(string(ulT.ActualMCSSelectionMode), "scheduler_grant")), ...
        "UL raw trials must disclose scheduler grants as the applied operating-point source.");
    assert(all(isfinite(double(ulT.AppliedAWGNSNR_dB))), ...
        "Baseline UL raw trials must publish the grant-level waveform replay AWGN SNR.");
    assert(all(strcmpi(string(ulT.AppliedAWGNSNRSource), "grant_level_waveform_replay_awgn_snr")), ...
        "Baseline UL raw trials must label applied AWGN SNR as waveform replay evidence.");
    assert(all(isfinite(double(ulT.SystemLevelSINR_dB))), ...
        "Baseline UL raw trials must publish the system-level desired/interference/noise SINR estimate separately.");
    assert(all(strcmpi(string(ulT.SystemLevelSINRValueRole), "runtime_state_derived")), ...
        "Baseline UL raw trials must classify the system-level SINR as runtime-state-derived.");
    assert(all(isfinite(double(ulT.ReceiverHestSINR_dB))), ...
        "System-level UL raw trials must publish receiver-Hest SINR from waveform replay.");
    assert(all(strcmpi(string(ulT.ReceiverHestSINRSource), "receiver_hest_reference_signal_measurement")), ...
        "System-level UL raw trials must source receiver-Hest SINR from receiver Hest/CSI feedback.");
    assert(all(strcmpi(string(ulT.ReceiverHestSINRValueStatus), "OK")), ...
        "System-level UL raw trials must label receiver-Hest SINR as available replay evidence.");
    assert(all(~isfinite(double(ulT.DecoderTruthProxySINR_dB))), ...
        "System-level UL raw trials must not publish EVM-derived decoder-truth SINR.");
    assert(all(contains(lower(string(ulT.DecoderTruthProxySINRSource)), "not_decoder_truth") | ...
        contains(lower(string(ulT.DecoderTruthProxySINRSource)), "not_materialized")), ...
        "System-level UL raw trials must disclose decoder SINR proxy quarantine/unavailability.");
    assert(all(strcmpi(string(ulT.DecoderTruthProxySINRValueStatus), "unavailable")), ...
        "System-level UL raw trials must keep decoder-side EVM SINR proxy unavailable in primary truth.");
    assert(all(strcmpi(string(ulT.ExplicitPrecoderReplayStatus), "materialized")), ...
        "System-level UL raw trials must label per-grant precoder replay evidence as materialized.");
    assert(all(strcmpi(string(ulT.ChannelArrayValueStatus), "approximate_system_context")), ...
        "System-level UL raw trials must label channel-array handling as approximate system context.");
end

ok = true;
end

function T = localReadCanonicalTable(pathStr)
opts = detectImportOptions(pathStr, "Delimiter", ",");
opts.VariableNamingRule = "preserve";
T = readtable(pathStr, opts);
end
