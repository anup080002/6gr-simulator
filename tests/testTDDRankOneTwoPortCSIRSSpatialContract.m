function ok = testTDDRankOneTwoPortCSIRSSpatialContract()
%TESTTDDRANKONETWOPORTCSIRSSPATIALCONTRACT Guard rank/port separation.
%
% A rank-one PDSCH uses one layer and one DM-RS port, but it may be
% precoded through two logical antenna ports.  The two-port CSI-RS
% resource set must occupy that same two-port/two-element spatial domain.

setup6GRSimToolkit("Verbose", false);
root = fileparts(fileparts(mfilename("fullpath")));
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile(root, ...
    "simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring_tdd.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scenario, string(tempname));

nLayers = double(sixgr.util.structGet(cfg, "phy.pdsch.nLayers", NaN));
nPorts = double(sixgr.util.structGet(cfg, "phy.pdsch.numPorts", NaN));
dmrsPorts = double(sixgr.util.structGet(cfg, ...
    "phy.pdsch.dmrs.portSet", []));
csiPorts = double(sixgr.util.structGet(cfg, "phy.csirs.nPorts", NaN));
initialPMI = double(sixgr.util.structGet(cfg, "phy.pdsch.PMI", NaN));
initialPMISource = string(sixgr.util.structGet(cfg, ...
    "phy.pdsch.PMISource", ""));

assert(nLayers == 1 && nPorts == 2, ...
    "TDD rank-one PDSCH must retain two logical precoding ports.");
assert(isequal(dmrsPorts(:).', 0), ...
    "Rank-one PDSCH must retain the configured single DM-RS port.");
assert(csiPorts == 2 && ...
    double(cfg.antenna.bs.numElements) == 2 && ...
    double(cfg.antenna.bs.numRFChains) == 2, ...
    "CSI-RS, physical elements and RF chains must share two-port authority.");
assert(initialPMI == 0 && ...
    initialPMISource == "configured_initial_dl_codebook_pmi_replaced_by_csi_feedback_when_available", ...
    "Two-port PDSCH requires an explicitly source-labelled bootstrap PMI.");

% TDD and FDD have different authored CSI-RS periods. Use this scenario's
% period/offset rather than importing the FDD four-slot fixture schedule.
csiSlot0=double(scenario.get('reference_signals.csi_rs_periodicity_slots'))+ ...
    double(scenario.get('reference_signals.csi_rs_offset_slots'));
[cfg, timeline] = sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg, csiSlot0+1, 1);
assert(double(timeline.AbsoluteSlotIndex0) == csiSlot0);
carrier = sixgr.phy.grid.makeCarrier(cfg);
reservation=sixgr.phy.frame.ssbPRBSymbolReservation(cfg,carrier,csiSlot0);
assert(isempty(reservation.ReservedCarrierRE0),'The spatial fixture must be SSB-free.');
[~, ~, pdsch] = sixgr.phy.grid.allocREsPDSCH(carrier, cfg);
% Strict execution requires the scheduler/frozen-grant boundary to turn
% the source-labelled bootstrap PMI into an immutable matrix.  The
% transmitter is not permitted to invent that matrix from configuration.
grant = localGrant(cfg, []);
grant.Slot=csiSlot0+1;
grant.GrantContextId="DL|tdd-rank1-two-port|absolute-slot="+string(csiSlot0);
grant.K0 = 0; % Explicit same-slot control for this spatial-only fixture.
grant = withAuthoredPDSCHDCI(cfg, grant);
phyGrant = sixgr.phy.grant.freezePHYGrant(cfg, "DL", grant, ...
    "SNR_dB", double(cfg.channel.snr_dB), "Frame", 1, "Slot", grant.Slot);
frozenLogicalW = double(phyGrant.PrecodingState.MatrixLogicalPorts);
assert(isequal(size(frozenLogicalW), [2 1]), ...
    "Frozen rank-one PDSCH scheduler precoder must be 2x1.");
[pmiCandidates, ~] = sixgr.phy.dl.pmiCodebookCandidates( ...
    cfg, 1, 2, "Mode", "type1_su_mimo");
Wcsi = double(pmiCandidates(initialPMI + 1).W);
Bcsirs = complex(double(cfg.phy.csirs.precoderMatrices(:,:,1)));
expectedElementW = Bcsirs * Wcsi;
assert(norm(double(phyGrant.PrecodingState.MatrixPhysicalPorts) - ...
        expectedElementW, "fro") <= 1e-12 && ...
    logical(phyGrant.PrecodingState.CSIRSPortBasisApplied) && ...
    double(phyGrant.PrecodingState.CSIResourceIndex) == 0, ...
    ["The frozen physical PDSCH beam must equal B_CSIRS*W_PMI for the " + ...
     "selected CRI; applying W_PMI directly in the element basis is invalid."]);
assert(string(phyGrant.PrecodingState.PMICodebookMatrixCSIPortsSHA256) == ...
        sixgr.phy.mimo.MatrixContract.digest(Wcsi), ...
    "Frozen CSI-port PMI matrix must be hash-auditable: actual=" + ...
    string(phyGrant.PrecodingState.PMICodebookMatrixCSIPortsSHA256) + ...
    " expected=" + sixgr.phy.mimo.MatrixContract.digest(Wcsi));
assert(string(phyGrant.PrecodingState.CSIRSPortToElementMatrixSHA256) == ...
        sixgr.phy.mimo.MatrixContract.digest(Bcsirs), ...
    "Frozen CSI-RS port-basis matrix must be hash-auditable.");
assert(string(phyGrant.PrecodingState.ComposedElementMatrixSHA256) == ...
        sixgr.phy.mimo.MatrixContract.digest(expectedElementW), ...
    "Frozen composed element-domain matrix must be hash-auditable.");
cfgFrozen = sixgr.phy.grant.applyPHYGrantToConfig(cfg, phyGrant);
precoder = sixgr.phy.dl.resolvePDSCHPrecoding(pdsch, cfgFrozen, ...
    "PrecodingMatrix", frozenLogicalW, "FixedReferenceMode", false);
assert(isequal(size(precoder.MatrixLogicalPorts), [2 1]), ...
    "Resolved rank-one PDSCH precoder must be 2x1.");
assert(precoder.PMI==initialPMI && precoder.PMIBasis=="csi_rs_port_basis", ...
    'The transmitted bootstrap retains its frozen CSI-port codebook identity.');
for selectedPMI=0:3
    selectedGrant=grant; selectedGrant.PMI=selectedPMI;
    selectedPHY=sixgr.phy.grant.freezePHYGrant(cfg,"DL",selectedGrant, ...
        "SNR_dB",double(cfg.channel.snr_dB),"Frame",1,"Slot",grant.Slot);
    selectedCfg=sixgr.phy.grant.applyPHYGrantToConfig(cfg,selectedPHY);
    selected=sixgr.phy.dl.resolvePDSCHPrecoding(pdsch,selectedCfg, ...
        "PrecodingMatrix",selectedPHY.PrecodingState.MatrixLogicalPorts);
    expected=Bcsirs*double(pmiCandidates(selectedPMI+1).W);
    assert(selected.PMI==selectedPMI && selected.PMIBasis=="csi_rs_port_basis" && ...
        norm(selected.MatrixPorts-expected,'fro')<1e-12 && ...
        selected.ComposedElementMatrixSHA256==sixgr.phy.mimo.MatrixContract.digest(expected), ...
        'CSI-basis PMI identity and the exact physically composed matrix must agree.');
    assert(selected.AppliedMatrixSHA256==selectedPHY.PrecodingState.SelectedMatrixSHA256, ...
        'Preserving PMI identity must not regenerate or normalize the selected waveform matrix.');
end
grant.PrecodingMatrixLogicalPorts = frozenLogicalW;
grant.LogicalPrecodingMatrix = frozenLogicalW;
grant.PrecodingMatrix = double(phyGrant.PrecodingState.MatrixPhysicalPorts);
grant.PrecodingActive = true;
assert(double(phyGrant.AntennaArchitecture.NumLayers) == 1 && ...
    double(phyGrant.AntennaArchitecture.NumLogicalPorts) == 2 && ...
    double(phyGrant.AntennaArchitecture.NumWaveformColumns) == 2, ...
    "Frozen DL grant collapsed rank, logical-port or waveform-port authority.");

[tx, info] = sixgr.phy.dl.PDSCH_Tx(cfg, ...
    "PHYGrant", phyGrant, "SchedulerGrantContext", grant, ...
    "CompactOutput", false);
assert(size(tx.PDSCHLayerSymbols, 2) == 1 && ...
    size(tx.PDSCHPortSymbols, 2) == 2 && ...
    size(tx.Grid, 3) == 2 && size(tx.Waveform, 2) == 2, ...
    "Runtime PDSCH did not preserve one layer over two waveform ports.");
assert(logical(tx.CSIRSRuntimeEvent.Scheduled) && ...
    logical(tx.CSIRSRuntimeEvent.Transmitted), ...
    "Configured post-burst CSI-RS occasion was not materialized.");
assert(double(tx.CSIRSRuntimeEvent.ResourceEvents(1).LogicalPortCount) == 2 && ...
    double(tx.CSIRSRuntimeEvent.ResourceEvents(1).PhysicalPortCount) == 2, ...
    "Runtime CSI-RS did not occupy the two-port physical spatial domain.");
assert(double(info.Precoding.NumLayers) == 1 && ...
    double(info.Precoding.NumLogicalPorts) == 2 && ...
    double(info.Precoding.NumPorts) == 2, ...
    "PDSCH evidence lost the rank-one/two-port distinction.");

[tx.Waveform, powerContext] = sixgr.rf.applyPowerContext( ...
    tx.Waveform, cfg, "DL", info); %#ok<ASGLU>
measurement = sixgr.phy.refsig.measureCSIRSRPFromWaveform( ...
    tx.Carrier, tx.CSIRS, tx.Waveform, ...
    "PhysicalIndices", tx.CSIRSPhysicalIndices, ...
    "AntennaAggregation", "sum_linear", ...
    "ReferencePlane", "focused_test_tx_connector");
branchPower = localParseVector(measurement.RSRPPerAntenna_dBm);
mappedRE = localParseVector(measurement.MappedREPerAntenna);
assert(logical(measurement.Available) && numel(branchPower) == 2 && ...
    all(isfinite(branchPower)) && all(mappedRE > 0), ...
    ["Exact Tx CSI-RS EPRE must be observed on both physical connectors; " + ...
     "logical-port CDM cancellation is not connector occupancy evidence."]);
assert(strcmpi(string(measurement.MeasurementMethod), ...
    "exact_nonzero_transmitted_csirs_re_per_physical_connector"), ...
    "Tx CSI-RS measurement must use the executed physical RE set.");
linearBranchmW = 10 .^ (branchPower ./ 10);
assert(abs(double(measurement.RSRP_dBm) - ...
    10 * log10(sum(linearBranchmW))) < 1e-10, ...
    "Aggregate Tx CSI-RS EPRE must be the linear connector-power sum.");

ok = true;
fprintf("[PASS] TDD rank-one PDSCH over two ports with two-port CSI-RS.\n");
end

function values = localParseVector(token)
token = erase(string(token), ["[", "]"]);
values = sscanf(char(token), "%f").';
end

function grant = localGrant(cfg, W)
pdsch = cfg.phy.pdsch;
grant = struct( ...
    "Direction", "DL", "Frame", 1, "Slot", 6, ...
    "RNTI", 1, "UEIndex", 1, "ServingCell", 1, ...
    "PRBSet", double(pdsch.prbSet(:).'), ...
    "SymbolAllocation", double(pdsch.symbolAllocation(:).'), ...
    "Modulation", char(string(pdsch.modulation)), ...
    "NumLayers", 1, "Layers", 1, "NumLogicalPorts", 2, ...
    "TargetCodeRate", double(pdsch.codeRate), ...
    "MCSIndex", double(pdsch.mcsIndex), "MCS", double(pdsch.mcsIndex), ...
    "PrecodingMatrix", double(W), "PrecodingActive", true, ...
    "ExactPHYFeasibilityChecked", true, "ExactPHYFeasible", true, ...
    "GrantContextId", "DL|tdd-rank1-two-port|frame=1|slot=6", ...
    "HARQ", struct("HarqID", 0, "NDI", true, "RV", 0, ...
        "IsRetransmission", false));
end
