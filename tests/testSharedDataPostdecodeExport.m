function ok=testSharedDataPostdecodeExport()
% Existing bounded shared SRS/DCI/PUSCH fixture through production exports.
% This is NOT the full-band H4 scenario or statistical qualification.
setup6GRSimToolkit('Verbose',false);
folder=fullfile(pwd,'results','lls','shared_data_postdecode_export', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
symbols=["testSharedPUSCHChannelArtifacts","sixgr.phy.srs.pilotChannelNMSE", ...
    "sixgr.report.buildReceiverChannelEstimateTable", ...
    "sixgr.truth.exportSharedDataChannelEstimate","sixgr.truth.sharedDataScoringWaveformReference", ...
    "sixgr.phy.ul.PUSCH_Rx","sixgr.truth.bindSharedRFExecutionEvidence"];
files=arrayfun(@(s)string(which(s)),symbols);
hashes=arrayfun(@(f)string(sixgr.util.sha256File(f)),files);
ok=testSharedPUSCHChannelArtifacts('TDD',false,false,false,false,false,false,folder);
assert(ok && isequal(hashes,arrayfun(@(f)string(sixgr.util.sha256File(f)),files)));
T=sixgr.util.csvReadTable(fullfile(folder,'received_pusch.csv'),'TextType','string');
assert(height(T)==1 && T.NMSEScoringAvailable && isfinite(T.NMSE_dB) && ...
    ~T.ChannelEstimateReferenceUsedByReceiver && T.ChannelEstimateComparedValues>0 && ...
    isfile(fullfile(folder,T.ChannelEstimateResourcesCSV)) && ...
    isfile(fullfile(folder,T.ChannelEstimateMATFile)));
sixgr.util.jsonWrite(fullfile(folder,'postdecode_export_receipt.json'), ...
    struct('Scope',"existing_bounded_shared_receiver_and_production_export_fixture", ...
    'Completed',true,'ScenarioAccepted',false,'FullBandH4Executed',false, ...
    'StatisticallyQualified',false,'SourceFiles',files,'SourceSHA256',hashes));
fprintf('SHARED_DATA_POSTDECODE_EXPORT_PASS folder=%s full_band_H4_executed=0\n',folder);
end
