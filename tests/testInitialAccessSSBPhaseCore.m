verifyEqual(testCase, height(expectedBursts), 360);

for rowIndex = 1:height(validInput)
    inputRow = validInput(rowIndex, :);
    resolved = sixgr.phy.ia.SSBCaseResolver.fromVectorRow(inputRow);
    timing = localTimingStruct(resolved);
    plan = sixgr.phy.ia.SSBBurstPlan.fromTiming(timing, ...
        "ActiveBitmap", inputRow.ActiveBitmap, ...
        "StrictBitmapRequired", true);
