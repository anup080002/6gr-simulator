end

function identifier = localCaptureError(fcn)
identifier = "";
try
    fcn();
catch cause
    identifier = string(cause.identifier);
end
end

function tableOut = localReadStringTable(pathIn)
options = detectImportOptions(pathIn, "TextType", "string");
options = setvartype(options, options.VariableNames, "string");
tableOut = readtable(pathIn, options);
end

function identifier = localExpectedExtensionError(procedure)
switch lower(string(procedure))
    case "two_step_ra"
        identifier = "sixgr:phy:ia:UnsupportedTwoStepRA";
    case "cfra"
        identifier = "sixgr:phy:ia:UnsupportedCFRA";
    case "beam_failure_recovery"
        identifier = "sixgr:phy:ia:UnsupportedBFR";
    case "sul_access"
        identifier = "sixgr:phy:ia:UnsupportedSUL";
    case "ntn_access"
        identifier = "sixgr:phy:ia:UnsupportedNTNAccess";
    case {"redcap_access", "eredcap_access"}
        identifier = "sixgr:phy:ia:UnsupportedRedCapAccess";
    otherwise
        error("sixgr:test:UnknownInitialAccessExtension", ...
            "Unknown extension procedure %s.", string(procedure));
end
end
