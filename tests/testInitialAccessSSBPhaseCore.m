function testSSBResourceOwnership(testCase)
inputPath = fullfile(testCase.TestData.VectorRoot, ...
    "ssb_re_mapping_test_vectors.csv");
expectedPath = fullfile(testCase.TestData.VectorRoot, ...
    "expected_ssb_re_ownership.csv");
inputs = localReadStringTable(inputPath);
expected = localReadStringTable(expectedPath);
verifyEqual(testCase, height(expected), 3840);

for inputIndex = 1:height(inputs)
    inputRow = inputs(inputIndex, :);
    actual = sixgr.phy.ia.SSBResourceOwnershipMap.resolve( ...
        str2double(inputRow.NCellID));
    expectedRows = expected(expected.CaseID == inputRow.CaseID, :);
    verifyEqual(testCase, height(actual.Rows), 960);
    verifyEqual(testCase, string(actual.Rows.Owner), ...
        string(expectedRows.Owner), ...
        sprintf("Owner mismatch for %s.", inputRow.CaseID));
    verifyEqual(testCase, double(actual.Rows.Symbol0), ...
        str2double(expectedRows.Symbol0));
    verifyEqual(testCase, double(actual.Rows.Subcarrier0), ...
        str2double(expectedRows.Subcarrier0));
    verifyEqual(testCase, double(actual.Rows.Index0), ...
        str2double(expectedRows.Index0));
    counts = groupsummary(actual.Rows, "Owner");
    localVerifyOwnerCount(testCase, counts, "PSS", 127);
    localVerifyOwnerCount(testCase, counts, "SSS", 127);
    localVerifyOwnerCount(testCase, counts, "PBCH", 432);
    localVerifyOwnerCount(testCase, counts, "PBCH_DMRS", 144);
    localVerifyOwnerCount(testCase, counts, "ZERO", 130);
end
end

function testSSBBurstBitmapAndCandidateTiming(testCase)
vectors = localReadVectors(testCase);
validInput = vectors.Input(lower(vectors.Input.ExpectedValid) == "true", :);
expectedBursts = localReadStringTable(fullfile( ...
    testCase.TestData.VectorRoot, ...
    "expected_ssb_burst_candidates.csv"));
