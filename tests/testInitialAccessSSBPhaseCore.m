        expectedBursts.CaseID == inputRow.CaseID, :);
    verifyEqual(testCase, double(plan.Rows.SSBIndex0), ...
        str2double(expectedRows.SSBIndex0));
    verifyEqual(testCase, double(plan.Rows.CandidateSymbol0), ...
        str2double(expectedRows.CandidateSymbol0));
    verifyEqual(testCase, logical(plan.Rows.Active), ...
        localLogicalColumn(expectedRows.Active));
    verifyEqual(testCase, double(plan.Rows.AbsoluteSymbol0), ...
        str2double(expectedRows.ExpectedAbsoluteSymbol0));
