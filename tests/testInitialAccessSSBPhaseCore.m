function localVerifyCaseFamily(testCase, caseLetter)
vectors = localReadVectors(testCase);
mask = lower(vectors.Input.ExpectedValid) == "true" & ...
    upper(vectors.Input.DeclaredSSBCase) == caseLetter;
inputs = vectors.Input(mask, :);
verifyGreaterThan(testCase, height(inputs), 0);
for rowIndex = 1:height(inputs)
    inputRow = inputs(rowIndex, :);
    expectedRow = vectors.Expected( ...
        vectors.Expected.CaseID == inputRow.CaseID, :);
    verifyEqual(testCase, height(expectedRow), 1);
    actual = sixgr.phy.ia.SSBCaseResolver.fromVectorRow(inputRow);
    verifyEqual(testCase, actual.ResolvedCase, ...
        string(expectedRow.ResolvedCase));
    verifyEqual(testCase, actual.ResolvedSSBSCSKHz, ...
        str2double(expectedRow.ResolvedSSBSCS_kHz));
    verifyEqual(testCase, actual.ResolvedLmax, ...
        str2double(expectedRow.ResolvedLmax));
    verifyEqual(testCase, actual.CandidateSymbols0Based, ...
        localPipeNumeric(expectedRow.CandidateSymbols0Based));
    verifyEqual(testCase, actual.NumCandidates, ...
        str2double(expectedRow.NumCandidates));
    verifyEqual(testCase, actual.PeriodicityMs, ...
        str2double(expectedRow.Periodicity_ms));
end
end

