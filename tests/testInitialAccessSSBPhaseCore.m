function testInitialAccessCapabilityRegistry(testCase)
profile = sixgr.phy.ia.InitialAccessSpecificationProfile.resolve();
verifyEqual(testCase, profile.ProfileID, ...
    "fr1_four_step_ra_rrc_connection_strict_r18");
verifyEqual(testCase, profile.Specifications.TS38211, ...
    "3GPP TS 38.211 V18.8.0");
verifyEqual(testCase, profile.Specifications.TS38331, ...
    "3GPP TS 38.331 V18.9.0");
verifyFalse(testCase, profile.ProxyAllowed);
verifyFalse(testCase, profile.FallbackAllowed);

plan = sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve();
verifyTrue(testCase, plan.Executable);
verifyEqual(testCase, plan.FallbackCount, 0);
verifyEqual(testCase, plan.StateMutationCount, 0);
verifyError(testCase, @() ...
    sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve( ...
    "Procedure", "two_step_ra"), ...
    "sixgr:phy:ia:UnsupportedTwoStepRA");
verifyError(testCase, @() ...
    sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve( ...
    "Procedure", "cfra"), ...
    "sixgr:phy:ia:UnsupportedCFRA");
verifyError(testCase, @() ...
    sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve( ...
    "Procedure", "beam_failure_recovery"), ...
    "sixgr:phy:ia:UnsupportedBFR");
verifyError(testCase, @() ...
    sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve( ...
    "Procedure", "sul_access"), ...
    "sixgr:phy:ia:UnsupportedSUL");
verifyError(testCase, @() ...
    sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve( ...
    "Procedure", "ntn_access"), ...
    "sixgr:phy:ia:UnsupportedNTNAccess");
verifyError(testCase, @() ...
    sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve( ...
    "Procedure", "eredcap_access"), ...
    "sixgr:phy:ia:UnsupportedRedCapAccess");

coverage = localReadStringTable(fullfile( ...
    testCase.TestData.VectorRoot, ...
    "initial_access_declared_coverage_matrix.csv"));
verifyEqual(testCase, height(coverage), 271);
declaredCount = 0;
unsupportedCount = 0;
for rowIndex = 1:height(coverage)
    row = coverage(rowIndex, :);
    if row.ExpectedStatus == "DECLARED"
        resolved = sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve( ...
            "Profile", row.Profile, ...
            "Procedure", row.RandomAccessProcedure);
        verifyTrue(testCase, resolved.Executable);
        verifyEqual(testCase, resolved.FallbackCount, 0);
        declaredCount = declaredCount + 1;
    else
        actual = localCaptureError(@() ...
            sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve( ...
            "Profile", row.Profile, ...
            "Procedure", row.RandomAccessProcedure));
        verifyEqual(testCase, actual, ...
            localExpectedExtensionError(row.RandomAccessProcedure), ...
            sprintf("Wrong extension gate for %s.", row.TupleID));
        unsupportedCount = unsupportedCount + 1;
    end
end
verifyEqual(testCase, declaredCount, 264);
verifyEqual(testCase, unsupportedCount, 7);
end

