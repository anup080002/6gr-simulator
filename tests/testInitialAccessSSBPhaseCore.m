function values = localPipeNumeric(textValue)
parts = split(string(textValue), "|");
values = str2double(parts(:)).';
end

function values = localLogicalColumn(raw)
values = lower(strtrim(string(raw))) == "true";
end

function localVerifyOwnerCount(testCase, counts, owner, expected)
mask = string(counts.Owner) == string(owner);
