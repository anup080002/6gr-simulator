cfg = localProductionConfig();
[~, ~, tx] = sixgr.phy.dl.SSB_Tx(cfg, ...
    "NumSubframes", 1, "TimingOnly", true);
verifyEqual(testCase, logical(tx.SSBBurstPlan.ActiveBitmap), ...
    logical([1 0 1 0 1 0 1 0]));
verifyEqual(testCase, double(tx.SSBBurstPlan.ActiveSSBIndices0Based), ...
    [0 2 4 6]);
