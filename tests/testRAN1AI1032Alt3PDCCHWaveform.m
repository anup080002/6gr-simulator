function ok=testRAN1AI1032Alt3PDCCHWaveform()
%TESTRAN1AI1032ALT3PDCCHWAVEFORM Corrected H0 over received control IQ.
% Focused control-chain evidence only, not a BLER or system result.
setup6GRSimToolkit('Verbose',false);
previousRNG=rng; rngCleanup=onCleanup(@()rng(previousRNG)); %#ok<NASGU>
rng(103232,'twister');
s=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_four_port_connected_research_ul_fixture.yaml');
cfg=sixgr.lls6g.buildInternalConfig(s,tempname);
name="experimental_6gr_ai1032_alt3";
cfg.phy.pusch.mcsTable=char(name);
cfg.phy.pusch.experimentalMCSTable=sixgr.phy.research.resolveExperimentalMCSTable(name);
cfg.phy.pusch.mcsIndex=32;
cfg.phy.pusch.modulation='1024QAM';
cfg.phy.pusch.codeRate=805.5/1024;
cfg=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,31);
context=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,'0_1');
schema=sixgr.phy.pdcch.DCISchemaEngine.resolve(context);
fields=struct();
for def=schema.Definitions(:).'
    fields.(char(def.Name))=def.ValueMin;
end
width=double(cfg.phy.carrier.NSizeGrid);
fields.frequency_resource_assignment=sixgr.phy.pdcch.rivEncode(0,width,width);
fields.mcs=32;
fields.ndi=1;
fields.rv=0;
fields.dmrs_sequence_initialization=1;
fields.precoding_information_and_number_of_layers= ...
    sixgr.phy.pdcch.ULPrecodingField.encode(context.Data,2,0);
fields.antenna_ports=sixgr.phy.pdcch.ULReferenceSignaling.encodeAntenna( ...
    context.Data,2,0:1,2,1);
packed=sixgr.phy.pdcch.DCIPacker.pack(fields,context);
tx=sixgr.link.preparePDCCHTransmission(cfg,'DCIBits',packed.Bits, ...
    'RNTI',cfg.phy.pusch.RNTI);
[rx,info]=sixgr.phy.dl.PDCCH_Rx(tx.TransmitSamples,cfg, ...
    'SampleRate_Hz',tx.SampleRateHz);
assignment=sixgr.phy.pdcch.materializeConnectedDCI(rx,info,cfg);
assert(assignment.MCS==32 && assignment.Modulation=="1024QAM" && ...
    abs(assignment.TargetCodeRate-805.5/1024)<1e-14 && ...
    assignment.NumLayers==2 && ~assignment.RequiresHARQHistory && ...
    ~assignment.StandardNR && ...
    rx.DecodedDCI.Schema.SchemaVersion=="sixgr_research_connected_ul_6bit/v1", ...
    'sixgr:ran1ai1032:Alt3ReceivedControl', ...
    'Blind received H0 control does not retain the corrected six-bit grant.');
allocation=sixgr.phy.pdcch.connectedDataAllocation(cfg,assignment);
payload=int8(randi([0 1],allocation.NominalTBSBits,1));
ue=sixgr.link.ReceivedULHARQState(cfg);
[pusch,~,ue]=ue.transmit(cfg,assignment,payload,[]); %#ok<ASGLU>
assert(pusch.TransportBlockSize==numel(payload) && ...
    pusch.Modulation=="1024QAM" && ...
    pusch.TransmissionAuthority=="received_dci_and_ue_new_tb_payload" && ...
    pusch.ReceivedDCIAssignmentDigest==assignment.AssignmentDigest && ...
    isequal(pusch.TransportBlock,payload), ...
    'sixgr:ran1ai1032:Alt3ReceivedPUSCH', ...
    'A decoded six-bit H0 grant must own the actual UE-coded new transport block.');
later=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,41);
laterContext=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(later,'0_1');
fields.mcs=36; fields.rv=2; % Same NDI/process: stored-TBS Qm=10 only.
stored=sixgr.phy.pdcch.DCIPacker.pack(fields,laterContext);
storedTX=sixgr.link.preparePDCCHTransmission(later,'DCIBits',stored.Bits, ...
    'RNTI',later.phy.pusch.RNTI);
[storedRX,storedInfo]=sixgr.phy.dl.PDCCH_Rx(storedTX.TransmitSamples,later, ...
    'SampleRate_Hz',storedTX.SampleRateHz);
storedAssignment=sixgr.phy.pdcch.materializeConnectedDCI(storedRX,storedInfo,later);
assert(storedAssignment.MCS==36 && storedAssignment.RequiresHARQHistory && ...
    isnan(storedAssignment.TargetCodeRate));
localReject(@()sixgr.phy.pdcch.connectedDataAllocation(later,storedAssignment), ...
    'sixgr:phy:pdcch:ReceivedHARQHistoryRequired');
[retry,~,ue]=ue.transmit(later,storedAssignment,[],[]); %#ok<ASGLU>
assert(retry.UEHARQIsRetransmission && retry.UEHARQAttempt==2 && ...
    retry.TransportBlockSize==pusch.TransportBlockSize && ...
    isequal(retry.TransportBlock,payload) && ...
    retry.Modulation=="1024QAM" && ...
    retry.ReceivedDCIAssignmentDigest==storedAssignment.AssignmentDigest, ...
    'sixgr:ran1ai1032:Alt3StoredTBSHARQ', ...
    'Stored-TBS codepoint must reuse the prior process payload and coding state.');
ok=true;
fprintf('RAN1_AI1032_ALT3_PDCCH_WAVEFORM_PASS mcs=%d bits=%d rank=%d tbs=%d stored_mcs=%d retries=%d\n', ...
    assignment.MCS,numel(packed.Bits),assignment.NumLayers,pusch.TransportBlockSize, ...
    storedAssignment.MCS,retry.UEHARQAttempt);
end

function localReject(fn,id)
try
    fn();
catch ME
    assert(strcmp(ME.identifier,id),'Expected %s, got %s: %s',id,ME.identifier,ME.message);
    return;
end
error('test:MissingRejection','Expected %s.',id);
end
