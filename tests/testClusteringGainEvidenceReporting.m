function [ok,result]=testClusteringGainEvidenceReporting()
% One real reporting invocation over declared legacy metadata, no PHY run.
setup6GRSimToolkit('Verbose',false);
folder=fullfile(pwd,'results','validation','clustering_gain_evidence_reporting', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
assert(~isfolder(folder),'Never overwrite retained evidence.');
layout=sixgr.report.resultLayout(folder);
sixgr.util.ensureFolder(layout.RFCSVDir);
scfg=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_tdd_5mhz_rank2_4tx2rx_awgn_0db.yaml');
data=scfg.toStruct();
data.output.artifact_contract_engine.enabled=false;
data.energy_efficiency.common_channel_clustering_enabled=true;
scfg=sixgr.lls6g.config.ScenarioConfig(data);
cfg=sixgr.lls6g.buildInternalConfig(scfg,folder);
% Missing, finite-zero and signed legacy values are NOT paired execution
% evidence. Even an AVAILABLE label alone cannot supply baseline identity.
probe=table(repmat("prach_common_channel_clustering_energy_effect",4,1), ...
    repmat("system",4,1),repmat("delta_j",4,1),[NaN;0;2;-1], ...
    repmat("",4,1),repmat("J",4,1), ...
    ["NOT_EVALUATED";"NOT_EVALUATED";"AVAILABLE";"AVAILABLE"], ...
    repmat("declared_legacy_probe_no_paired_execution",4,1), ...
    'VariableNames',{'MetricKey','Entity','Statistic','Value','ValueText','Unit','Availability','Notes'});
original=probe;
path=fullfile(layout.RFCSVDir,'probe_rf_energy.csv');
sixgr.util.csvWriteTable(path,probe,'PreserveSchema',true,'RoundTripNumericText',true);
digest=string(sixgr.util.sha256File(path));
manifest=struct('CodeVersion',"test",'CodeDetail',"declared_metadata_no_PHY", ...
    'RandomSeed',1,'GeneratedUTC',"test",'RunnerProfile',"test", ...
    'RunCompletion',"completed",'DeterministicMode',"test");
out=sixgr.truth.exportLLSReportingBundle(folder,scfg,cfg,struct('Ok',false),manifest, ...
    struct('StartedUTC',"test",'ElapsedSeconds',1),struct());
checkRows(out.CategoryRows);
checkRows(sixgr.util.csvReadTable(out.DetailCSV,'TextType','string'));
coverage=out.Coverage(out.Coverage.MetricKey=="clustering_gain_penalty",:);
assert(height(coverage)==1 && ~coverage.CountsTowardCoverage && ...
    coverage.CoveredRowCount==0 && coverage.Availability=="not_available", ...
    'Policy configuration or legacy finite values must not count as paired gain coverage.');
assert(isequaln(probe,original)&&digest==string(sixgr.util.sha256File(path)), ...
    'Preserve every original probe value and source byte.');
result=struct('EvidenceRoot',string(folder),'OriginalProbeSHA256',digest, ...
    'Scope',"declared_legacy_probe_to_actual_public_report_no_paired_execution", ...
    'PHYExecutions',0,'PairedExecutionEvidence',false);
ok=true;
fprintf('CLUSTERING_GAIN_REPORTING_PASS original_probe_rows=4 report_invocations=1 PHY_executions=0 root=%s\n',folder);
end

function checkRows(rows)
selected=rows(rows.MetricKey=="clustering_gain_penalty",:);
assert(height(selected)==1 && selected.Statistic=="delta_energy_j" && ...
    selected.Availability=="not_available" && ~selected.CountsTowardCoverage && ...
    isnan(selected.ValueNumeric) && selected.Unit=="J" && ...
    contains(selected.Notes,"paired-execution contract"), ...
    'Missing matched executions must stay unavailable, never manufactured zero gain.');
end
