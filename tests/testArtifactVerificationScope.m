function ok = testArtifactVerificationScope()
%TESTARTIFACTVERIFICATIONSCOPE E2E-only artifact checks must be mode scoped.

setup6GRSimToolkit("Verbose", false);

cfg = sixgr.config.defaultConfig();
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmp, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", 0.02, ...
    "E2EMaxSlots", 24, ...
    "E2EUECount", 2, ...
    "E2ETrafficModel", "xr", ...
    "E2EAirModel", "truth", ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", true, ...
    "GenerateCampaignPlots", false, ...
    "E2EStrictValidation", true, ...
    "E2ETruthFastAWGNPath", false, ...
    "E2ETruthMaxSlots", 48);

assert(rep.Ok, "E2E-only truth run with artifact verification should pass.");

layout = sixgr.report.resultLayout(char(string(rep.RunFolder)));
req = readtable(layout.RequiredOutputsCSV, ...
    "VariableNamingRule", "preserve");
paths = lower(string(req.RequiredPath));
hasSystem = contains(paths, "\system\") | contains(paths, "/system/");
hasLink = contains(paths, "\air_interface\") | contains(paths, "/air_interface/");
assert(~any(hasSystem), "E2E-only required outputs should not include system artifacts.");
assert(~any(hasLink), "E2E-only required outputs should not include link artifacts.");

art = rep.ArtifactCheck.Table;
pat = lower(string(art.Pattern));
sysMask = logical(art.Required) & (contains(pat, "system/") | contains(pat, "system\\"));
linkMask = logical(art.Required) & (contains(pat, "air_interface/") | contains(pat, "air_interface\\"));
assert(~any(sysMask), "Mode-scoped artifact checklist should not require system artifacts for E2E-only runs.");
assert(~any(linkMask), "Mode-scoped artifact checklist should not require link artifacts for E2E-only runs.");

ok = true;
end
