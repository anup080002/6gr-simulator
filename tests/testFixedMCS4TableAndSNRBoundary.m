function ok = testFixedMCS4TableAndSNRBoundary()
%TESTFIXEDMCS4TABLEANDSNRBOUNDARY Keep MCS-table and SNR semantics explicit.
%
% An MCS index is not an operating point without its TS 38.214 table.
% This regression prevents a qam256-table MCS 4 (R=602/1024) from being
% mistaken for qam64-table MCS 4 (R=308/1024), and prevents a 1x1,
% per-occupied-RE -5 dB result from being compared with a link that includes
% receive-diversity or array gain.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

table1 = sixgr.link.resolveMCSProfile("qam64_table1", 4);
table2 = sixgr.link.resolveMCSProfile("qam256_table2", 4);
table3 = sixgr.link.resolveMCSProfile("qam64LowSE_table3", 4);

assert(table1.Valid && table2.Valid && table3.Valid && ...
    all([table1.Qm table2.Qm table3.Qm] == 2), ...
    "MCS 4 must resolve to QPSK in all three supported NR MCS tables.");
assert(abs(table1.TargetCodeRate - 308/1024) < 1e-14 && ...
    abs(table2.TargetCodeRate - 602/1024) < 1e-14 && ...
    abs(table3.TargetCodeRate - 78/1024) < 1e-14, ...
    "MCS 4 target rates must match their distinct TS 38.214 tables.");

capacityAtMinus5 = log2(1 + 10^(-5/10));
assert(capacityAtMinus5 < table1.SpectralEfficiency && ...
    capacityAtMinus5 < table2.SpectralEfficiency && ...
    capacityAtMinus5 > table3.SpectralEfficiency, ...
    ["At a rank-1, 1x1 AWGN per-RE Es/N0 of -5 dB, even ideal capacity " ...
     "is below table-1/table-2 MCS 4 but above low-SE table-3 MCS 4."]);

fprintf("FixedMCS4TableAndSNRBoundary: C(-5 dB)=%.4f bit/RE; " + ...
    "SE(table1/table2/table3)=%.4f/%.4f/%.4f PASS\n", ...
    capacityAtMinus5, table1.SpectralEfficiency, ...
    table2.SpectralEfficiency, table3.SpectralEfficiency);
ok = true;
end
