function ok=testSSBCandidateCoordinateEvidence()
setup6GRSimToolkit('Verbose',false);
cfg.phy.carrier=struct('SubcarrierSpacing',15,'CyclicPrefix','normal');
cfg.phy.ssb.timing=struct('SSBSubcarrierSpacingKHz',30,'CandidateStartSymbols',[2 8 16 22]);
T=sixgr.truth.ssbCandidateCoordinateEvidence(cfg,(0:3)',repmat(614400,4,1),repmat(30720000,4,1));
assert(isequal(T.SSBCandidateCarrierSlot0Based,[20;20;20;20]) && ...
    isequal(T.SSBCandidateSymbolWithinSlot0Based,[1;4;8;11]) && ...
    isequal(T.SSBCandidateNativeSlot0Based,[40;40;41;41]) && ...
    isequal(T.SSBCandidateNativeSymbolWithinSlot0Based,[2;8;2;8]) && ...
    isequal(T.SSBCandidateCPStartSample-614400,[2208;8784;17568;24144]) && ...
    isequal(T.SSBCandidateEndSampleExclusive-614400,[6592;13168;21952;28528]) && ...
    all(T.SSBCandidateCommonBoundaryAligned==1));
% Same-numerology legacy coordinates, now including the actual burst epoch.
cfg.phy.carrier.SubcarrierSpacing=30;
S=sixgr.truth.ssbCandidateCoordinateEvidence(cfg,(0:3)',repmat(614400,4,1),repmat(30720000,4,1));
assert(isequal(S.SSBCandidateCarrierSlot0Based,S.SSBCandidateNativeSlot0Based) && ...
    isequal(S.SSBCandidateSymbolWithinSlot0Based,S.SSBCandidateNativeSymbolWithinSlot0Based));
failed=sixgr.truth.ssbCandidateCoordinateEvidence(cfg,NaN,614400,30720000);
assert(all(isnan(failed{1,1:8})),'Failed detection must not invent a received SSB index/position.');
fprintf('SSB_CANDIDATE_CLOCK_PASS: native/common sample-time conversion and nonzero burst epoch.\n');
ok=true;
end
