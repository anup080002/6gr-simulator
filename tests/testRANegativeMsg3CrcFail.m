function ok = testRANegativeMsg3CrcFail()
res = sixgr.phy.ra.runFourStepRA(raStrictAnchorConfig(), "FaultMode", "msg3_pusch_corrupted", "WriteArtifacts", false);
assert(~logical(res.RACompleted) && ~logical(res.StrictOk), "Corrupt MSG3 must not complete RA.");
assert(string(res.FailureReason) == "msg3_pusch_crc_fail", "MSG3 CRC failure must be explicit.");
assert(strlength(res.Msg3TransmittedPayloadHex)>0 && strlength(res.Msg3PayloadHex)==0, ...
    "Transmitted Msg3 bytes must never rescue a failed receiver payload.");
row=res.ArtifactTables.msg3_pusch_trials;
assert(~row.ULSCHCrcPass && strlength(row.PayloadHex)==0 && ...
    row.TransmittedPayloadHex==res.Msg3TransmittedPayloadHex);
msg4Fields=res.ArtifactTables.msg4_dci_fields;
assert(height(msg4Fields)==0 && width(msg4Fields)==13 && ...
    isequal(string(msg4Fields.Properties.VariableNames), ...
    ["RunId","UEId","AbsoluteSlot","RNTI","Endpoint","FieldName", ...
    "WidthBits","BitStart","BitEnd","Value","ContextDigest", ...
    "ReferenceSource","EvidenceRole"]), ...
    "A Msg3 termination must retain the producer-owned empty Msg4 DCI schema.");
ok = true;
end
