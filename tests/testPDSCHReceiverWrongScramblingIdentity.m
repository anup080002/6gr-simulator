function ok = testPDSCHReceiverWrongScramblingIdentity()
%TESTPDSCHRECEIVERWRONGSCRAMBLINGIDENTITY Wrong NID must fail CRC.

setup6GRSimToolkit("Verbose", false);
fixture = StrictPDSCHChainFixture.create(1);
tx = sixgr.pdsch.PDSCHTransmitter( ...
    fixture.TransportBlocks,fixture.Assignment,fixture.ResourcePlan, ...
    fixture.Carrier,fixture.ReferenceConfig, ...
    "PrecoderBundle",fixture.PrecoderBundle);
wrongReference = fixture.ReferenceConfig;
wrongData = wrongReference.toStruct();
wrongData.DataScramblingIdentityNID = ...
    mod(double(wrongReference.get("DataScramblingIdentityNID")) + 1,1024);
wrongReference = sixgr.pdsch.PDSCHReferenceSignalConfig(wrongData);
wrongPlan = localRebindReferenceDigest( ...
    fixture.ResourcePlan,fixture.Assignment,fixture.Carrier, ...
    wrongReference.ConfigurationDigest);
rx = sixgr.pdsch.PDSCHReceiver( ...
    tx.Waveform,fixture.Assignment,wrongPlan,fixture.Carrier, ...
    wrongReference,fixture.ReceiverConfig, ...
    "CodingPlans",tx.CodingPlans, ...
    "PrecoderBundle",fixture.PrecoderBundle);
assert(~rx.CRCPass && rx.CRCError, ...
    "Wrong scrambling identity must return a controlled CRC failure.");
fprintf("PDSCH strict RX wrong scrambling identity: controlled CRC failure pass\n");
ok = true;
end

function rebound = localRebindReferenceDigest( ...
        plan,assignment,carrier,referenceDigest)
context = struct( ...
    "PRBSet",double(plan.PRBSet), ...
    "SymbolAllocation",double(plan.SymbolAllocation), ...
    "GridNumPRB",double(carrier.NSizeGrid), ...
    "GridSymbolsPerSlot",double(carrier.SymbolsPerSlot), ...
    "BWPStartPRB",double(carrier.NStartGrid), ...
    "AbsoluteSlot",double(assignment.get("PDSCHAbsoluteSlot")), ...
    "UnavailableIndices",double(plan.OwnershipMap.UnavailableIndices), ...
    "DMRSIndicesPerPort",{plan.DMRSIndicesPerPort}, ...
    "PTRSIndicesPerPort",{plan.PTRSIndicesPerPort}, ...
    "DMRSLogicalPortSet",double(plan.DMRSLogicalPortSet), ...
    "PTRSLogicalPortSet",double(plan.PTRSLogicalPortSet), ...
    "LayerCountPerCodeword",double(plan.LayerCountPerCodeword), ...
    "QmPerCodeword",double(plan.QmPerCodeword), ...
    "CodeBlockCountPerCodeword",cellfun(@numel,plan.EPerCodeBlock), ...
    "ReferenceConfigurationDigest",string(referenceDigest));
rebound = sixgr.pdsch.PDSCHResourcePlan(plan.OwnershipMap,context);
end
