function ok = testYAMLReferenceSignalFeatureAuthority()
%TESTYAMLREFERENCESIGNALFEATUREAUTHORITY Guard YAML feature enable flags.

setup6GRSimToolkit("Verbose", false);
files = ["master_sinr_sweep.yaml", ...
    "webgui_sinr_sweep_64x4_mu_mimo_full.yaml", ...
    "webgui_sinr_sweep_64x4_mu_mimo_repair_slice.yaml"];
for index = 1:numel(files)
    scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
        pwd, "simulator", "configs", "scenarios", files(index)));
    cfg = sixgr.lls6g.buildInternalConfig(scenario, tempdir);
    expectedPTRS = logical(scenario.get( ...
        "reference_signals.ptrs_enabled"));
    expectedPTRSCorrection = logical(scenario.get( ...
        "reference_signals.ptrs_cpe_correction_enabled"));
    expectedSRS = logical(scenario.get( ...
        "reference_signals.srs_enabled"));
    expectedCSIRS = logical(scenario.get( ...
        "reference_signals.csi_rs_enabled"));
    expectedTRS = logical(scenario.get( ...
        "reference_signals.trs_enabled"));
    assert(cfg.phy.pdsch.enablePTRS == expectedPTRS && ...
        cfg.phy.pusch.enablePTRS == expectedPTRS && ...
        cfg.phy.ptrs.enable == expectedPTRS && ...
        cfg.pdsch6gr.EnablePTRS == expectedPTRS, ...
        "All PT-RS runtime aliases must equal the resolved YAML flag.");
    assert(cfg.phy.pdsch.ptrs.enableCPECorrection == expectedPTRSCorrection && ...
        cfg.phy.pusch.ptrs.enableCPECorrection == expectedPTRSCorrection && ...
        cfg.phy.ptrs.enableCPECorrection == expectedPTRSCorrection, ...
        "DL and UL PT-RS CPE correction must equal its YAML flag.");
    assert(cfg.phy.srs.enable == expectedSRS && ...
        cfg.phy.csirs.enable == expectedCSIRS && ...
        cfg.phy.trs.enable == expectedTRS, ...
        "SRS, CSI-RS, and TRS runtime flags must equal resolved YAML.");
    authority = cfg.runtime.features;
    assert(authority.ptrs.Enabled == expectedPTRS && ...
        authority.srs.Enabled == expectedSRS && ...
        authority.csi_rs.Enabled == expectedCSIRS && ...
        authority.trs.Enabled == expectedTRS, ...
        "The immutable runtime feature authority must equal YAML.");
    featureNames = fieldnames(authority);
    for featureIndex = 1:numel(featureNames)
        item = authority.(featureNames{featureIndex});
        assert(string(item.Authority) == "resolved_scenario_yaml" && ...
            any(string(item.Status) == ["configured_runtime_consumer_exact", ...
                "yaml_target_case_derived_runtime_consumer_exact"]) && ...
            strlength(string(item.SourceYAMLPath)) > 0 && ...
            ~isempty(item.RuntimeConsumerPaths), ...
            "Every feature must retain YAML provenance and runtime consumers.");
    end
    provenanceNames = string(cfg.runtime.ParameterProvenanceTable.Parameter);
    for featureIndex = 1:numel(featureNames)
        assert(any(provenanceNames == "runtime.features." + ...
            string(featureNames{featureIndex}) + ".Enabled"), ...
            "Feature %s must be present in provenance.", featureNames{featureIndex});
    end
    expectedPolicy = string(scenario.get( ...
        "reference_signals.ptrs_port_association_policy"));
    assert(string(cfg.phy.pdsch.ptrs.portAssociationPolicy) == ...
        expectedPolicy && string(cfg.phy.pusch.ptrs.portAssociationPolicy) == ...
        expectedPolicy, ...
        "PT-RS port association policy must be preserved from YAML.");
end

% A disabled YAML must block direct generators instead of permitting their
% object defaults to turn the signal back on.
disabledScenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    pwd, "simulator", "configs", "scenarios", "master_sinr_sweep.yaml"));
disabledCfg = sixgr.lls6g.buildInternalConfig(disabledScenario, tempdir);
localAssertThrows(@() sixgr.phy.dl.SSB_Tx(disabledCfg), ...
    "sixgr:phy:ssb:DisabledByYAML");
localAssertThrows(@() sixgr.phy.ul.SRS_Tx(disabledCfg), ...
    "sixgr:phy:srs:DisabledByYAML");
localAssertThrows(@() sixgr.phy.dl.PDCCH_Tx(disabledCfg), ...
    "sixgr:phy:pdcch:DisabledByYAML");
disabledCSI = sixgr.phy.dl.CSI_Feedback(1, 1, disabledCfg);
assert(~disabledCSI.ReportCQI && ~disabledCSI.ReportPMI && ...
    ~disabledCSI.ReportRI && ~disabledCSI.ReportCRI && ...
    disabledCSI.CSIPayloadBitLength == 0 && ...
    isempty(disabledCSI.CSIPayloadBits), ...
    "YAML-disabled CSI reporting must produce no report fields or payload.");

bad = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    pwd, "simulator", "configs", "scenarios", ...
    "webgui_sinr_sweep_64x4_mu_mimo_full.yaml")).toStruct();
bad.pusch.ptrs_enabled = false;
localAssertThrows(@() sixgr.lls6g.buildInternalConfig(bad, tempdir), ...
    "sixgr:config:ContradictoryRuntimeAuthority");
ok = true;
end

function localAssertThrows(fcn, identifier)
didThrow = false;
try
    fcn();
catch ME
    didThrow = strcmp(string(ME.identifier), string(identifier));
    if ~didThrow
        rethrow(ME);
    end
end
assert(didThrow, "Expected typed error %s.", identifier);
end
