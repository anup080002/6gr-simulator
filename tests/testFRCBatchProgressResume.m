function ok = testFRCBatchProgressResume()
%TESTFRCBATCHPROGRESSRESUME Resume an exact FRC point after one saved batch.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
root = tempname;
mkdir(root);
cleanup = onCleanup(@() rmdir(root, "s")); %#ok<NASGU>
progressDir = fullfile(root, "interrupted_progress");

args = { ...
    "SNRGrid_dB", 3.2, ...
    "ExecutionProfile", "smoke", ...
    "MinTransportBlocks", 2, ...
    "MaxTransportBlocks", 2, ...
    "BatchSize", 1, ...
    "MinimumBlockErrors", 0, ...
    "EvaluateSymmetricRegression", false, ...
    "RequireExactStandardExecution", true, ...
    "RequireExactDataChannelExecution", true, ...
    "ProgressDirectory", progressDir, ...
    "ProgressIdentitySHA256", "frc_batch_resume_regression", ...
    "ResumeProgress", true, ...
    "PrintTable", false, ...
    "Verbose", false};

interrupted = false;
try
    sixgr.conformance.runFRCPoint( ...
        "dl_r_pdsch_1_1_4_fdd_awgn", "awgn_static_1x2", ...
        args{:}, "ProgressObserver", @localStopAfterFirstBatch);
catch ME
    interrupted = string(ME.identifier) == ...
        "sixgr:tests:IntentionalFRCProgressStop";
    if ~interrupted
        rethrow(ME);
    end
end
assert(interrupted, ...
    "The focused test did not stop after its first persisted FRC batch.");

progressFiles = dir(fullfile(progressDir, "*", ...
    "frc_reference_progress.csv"));
checkpointFiles = dir(fullfile(progressDir, "*", ...
    "frc_point_checkpoint.mat"));
assert(numel(progressFiles) == 1 && numel(checkpointFiles) == 1, ...
    "An interrupted FRC batch must persist one progress CSV and checkpoint.");
progressPath = fullfile(progressFiles(1).folder, progressFiles(1).name);
checkpointPath = fullfile(checkpointFiles(1).folder, ...
    checkpointFiles(1).name);
P = readtable(progressPath, "TextType", "string");
assert(height(P) == 1 && P.CompletedTransportBlocks(1) == 1 && ...
    P.Status(1) == "IN_PROGRESS" && ...
    P.EvidenceClass(1) == ...
        "ACTUAL_FRC_TRUTH_EXECUTION_IN_PROGRESS" && ...
    P.ApproximationMode(1) == "none", ...
    "The interrupted progress row is not truthful or batch-exact.");
saved = load(checkpointPath);
assert(saved.CompletedTransportBlocks == 1 && ~saved.Completed, ...
    "The checkpoint must disclose one incomplete persisted batch.");

resumed = sixgr.conformance.runFRCPoint( ...
    "dl_r_pdsch_1_1_4_fdd_awgn", "awgn_static_1x2", args{:});
P = readtable(progressPath, "TextType", "string");
assert(P.CompletedTransportBlocks(1) == 2 && ...
    P.Status(1) == "COMPLETED" && ...
    P.EvidenceClass(1) == "ACTUAL_FRC_TRUTH_EXECUTION_COMPLETED", ...
    "The resumed FRC point did not finalize its progress evidence.");

baselineArgs = args;
progressArgIndex = find(cellfun(@(v) ...
    (ischar(v) || (isstring(v) && isscalar(v))) && ...
    string(v) == "ProgressDirectory", baselineArgs), 1, "first");
resumeArgIndex = find(cellfun(@(v) ...
    (ischar(v) || (isstring(v) && isscalar(v))) && ...
    string(v) == "ResumeProgress", baselineArgs), 1, "first");
baselineArgs{progressArgIndex + 1} = fullfile(root, "baseline");
baselineArgs{resumeArgIndex + 1} = false;
baseline = sixgr.conformance.runFRCPoint( ...
    "dl_r_pdsch_1_1_4_fdd_awgn", "awgn_static_1x2", ...
    baselineArgs{:});
ra = resumed.PointDetails{1}.TransportBlockAudit;
ba = baseline.PointDetails{1}.TransportBlockAudit;
assert(isequaln(resumed.Sweep, baseline.Sweep) && ...
    isequaln(ra.Delivered, ba.Delivered) && ...
    isequaln(ra.Attempts, ba.Attempts) && ...
    isequaln(ra.NoiseSeedByAttempt, ba.NoiseSeedByAttempt) && ...
    isequaln(ra.RVByAttempt, ba.RVByAttempt) && ...
    isequaln(ra.AbsoluteSlotByAttempt, ba.AbsoluteSlotByAttempt) && ...
    isequaln(ra.ChannelStartSampleByAttempt, ...
        ba.ChannelStartSampleByAttempt), ...
    "Resumed FRC evidence differs from uninterrupted deterministic truth.");

mismatch = false;
try
    sixgr.conformance.runFRCPoint( ...
        "dl_r_pdsch_1_1_4_fdd_awgn", "awgn_static_1x2", ...
        args{:}, "Seed", 38105);
catch ME
    mismatch = string(ME.identifier) == ...
        "sixgr:conformance:FRCPointProgressIdentityMismatch";
    if ~mismatch
        rethrow(ME);
    end
end
assert(mismatch, ...
    "A seed mismatch must fail closed against an existing FRC checkpoint.");
ok = true;
end

function localStopAfterFirstBatch(progressRow, checkpointPath)
assert(istable(progressRow) && height(progressRow) == 1 && ...
    progressRow.CompletedTransportBlocks(1) == 1 && ...
    isfile(checkpointPath), ...
    "The observer was called before durable batch evidence existed.");
error("sixgr:tests:IntentionalFRCProgressStop", ...
    "Intentional stop after the first durable FRC batch.");
end
