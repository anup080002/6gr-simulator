function ok=testPHYDiagnosticCSVConsumers()
% Deliberate CSV fixtures; this tests publication, not PHY performance.
setup6GRSimToolkit('Verbose',false);
root=fullfile(pwd,'results','diagnostics','phy_csv_consumers', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
layout=sixgr.report.resultLayout(root);
sixgr.util.ensureFolder(layout.ReportCSVDir); sixgr.util.ensureFolder(layout.ReportImageDir);
path=fullfile(layout.ReportCSVDir,'phy_signal_diagnostic_source.csv');
panels=["time_domain";"spectrum";"channel_estimate"; ...
    "pre_equalization_re_cloud";"post_equalization_constellation";"kpi"; ...
    repmat("channel_estimate_grid",9001,1)];
n=numel(panels);
T=table(repmat("snapshot_declared_fixture",n,1),panels,repmat("tx",n,1), ...
    (1:n)',ones(n,1),ones(n,1),repmat("DL",n,1), ...
    repmat("runtime_same_trial_phy_signal_snapshot",n,1), ...
    repmat("real_lls_evidence",n,1),repmat("runtime_phy_arrays_same_trial",n,1), ...
    repmat("available",n,1),ones(n,1),ones(n,1),ones(n,1), ...
    repmat(4660,n,1),repmat("declared_fixture_tb",n,1), ...
    'VariableNames',{'SnapshotID','Panel','Series','PointIndex','XValue','YValue', ...
    'Direction','CurveConstruction','truth_status','SourceArtifact','Status', ...
    'Frame','Slot','UEIndex','RNTI','TBId'});
T.Notes=repmat("quoted, metadata "+newline+"not another record",n,1);
sixgr.util.csvWriteTable(path,T,'PreserveSchema',true);
imwrite(zeros(2,2,3,'uint8'),fullfile(layout.ReportImageDir,'dl_phy_signal_diagnostic.png'));
s=sixgr.truth.scanPHYSignalDiagnosticCSV(path,127);
assert(s.RowCount==n && s.MaxChunkRows<=127 && s.TruthOK && s.DL.TupleConsistent);
assert(sum(s.PanelSeriesCounts.RowCount)==n && ...
    s.PanelSeriesCounts.RowCount(s.PanelSeriesCounts.Panel=="channel_estimate_grid")==9001);
a=sixgr.truth.phySignalDiagnosticAvailability(path,layout.ReportImageDir);
assert(a.Source=="observed" && a.DL=="derived" && a.UL=="not_available");
sixgr.truth.exportTop50VisualizationEvidenceInventory(root,struct());
% A bad final row must be found beyond the import block, not lost to a cap.
cases={"truth_status","proxy","truth_status_not_real_lls_evidence"; ...
    "SnapshotID","other","dl_snapshot_id_not_unique"; ...
    "TBId","other","dl_trial_tuple_not_unique"; ...
    "Direction","INVALID","source_direction_invalid"; ...
    "SourceArtifact","synthetic","source_artifact_not_runtime_phy_arrays_same_trial"};
for j=1:size(cases,1)
    bad=T; bad.(cases{j,1})(end)=cases{j,2};
    sixgr.util.csvWriteTable(path,bad,'PreserveSchema',true);
    a=sixgr.truth.phySignalDiagnosticAvailability(path,layout.ReportImageDir);
    assert(contains(a.Reason,cases{j,3}) && a.DL~="derived", ...
        'test:LateDiagnosticRowIgnored','Invalid final row was ignored: %s',cases{j,1});
end
sixgr.util.csvWriteTable(path,T([],:),'PreserveSchema',true);
s=sixgr.truth.scanPHYSignalDiagnosticCSV(path);
assert(s.RowCount==0);
sixgr.util.csvWriteTable(path,T,'PreserveSchema',true);
fprintf('PHY_CSV_CONSUMERS_PASS rows=%d block=127 fixture_root=%s\n',n,root);
ok=true;
end
