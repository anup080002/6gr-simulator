function ok=testLLSReceiverAuthorityPublicProjection()
% Declared publication fixtures only: no waveform, reception or admission.
% The publisher must preserve original evidence, including deliberately
% unknown/mixed values, rather than evaluate policy or repair the fixture.
setup6GRSimToolkit('Verbose',false);
contract=sixgr.truth.llsOutputContract();
meta=struct('logical_run_id',"declared_receiver_authority_projection",'run_id',17);
source=table([23;7;14],[0;1;NaN],[true;true;false], ...
    'VariableNames',{'Slot','CRCPass','CRCApplicable'});
numericFields=["ReceiverUsable","DecodeAttempted","DecodeUsable", ...
    "ChannelEstimateAttempted","ChannelEstimateAvailable", ...
    "ResourceExtractionAttempted","ResourceExtractionAvailable", ...
    "EqualizationAttempted","EqualizationAvailable", ...
    "DLSCHDecodeAttempted","DLSCHDecodeAvailable", ...
    "ULSCHDecodeAttempted","ULSCHDecodeAvailable","LLRAvailable","LLRFinite", ...
    "NoiseVarStrictFailure","StrictReceiverEvidenceOk","StrictOk", ...
    "PostEqSINRAvailable","PostEqSINRReceiverDerived", ...
    "DetectionApplicable","DetectionAttempted","DetectionSuccess","DetectionUsable", ...
    "MeasurementApplicable","MeasurementAttempted","MeasurementUsable", ...
    "MeasurementValue_dB","ChannelFadingApplied", ...
    "PDCCHReceiverDecodeOk","PDCCHDataAdmissionOk", ...
    "CountsTowardCoverage","PartialRowFlag","FinalizedFlag","IsWarmupFrame", ...
    "FallbackFlag","PlaceholderFlag"];
for name=numericFields, source.(name)=[1;0;NaN]; end
% Keep typed booleans too; optional passthrough must not coerce their class.
source.Crash=[false;false;true];
source.MeasurementAttemptKnown=[true;false;false];
source.ChannelExecutionEvidenceAvailable=[true;false;false];
textFields=["Status","FailureReason","ChannelEstimateSource","TruthStatus", ...
    "SINRValidationStatus","DetectionStatus","DetectionSource", ...
    "MeasurementStatus","MeasurementSource","MeasurementDefinition", ...
    "MeasurementValueRole","MeasurementValueStatus","MeasurementSummarySource", ...
    "ChannelModelApplied","ChannelFadingExecutionStatus", ...
    "ChannelExecutionEvidenceStatus","ChannelExecutionEvidenceSource", ...
    "ChannelExecutionTransmitterID","ChannelExecutionReceiverID","ChannelExecutionLinkID", ...
    "ChannelExecutionConfigurationEpoch","PDCCHTCIAdmissionStatus", ...
    "PrimaryTruthValueStatus","RowLifecycleState","NAReason", ...
    "RuntimeMaterializationStatus","RuntimeEvidenceSource","RuntimeEvidenceStatus"];
for name=textFields, source.(name)=["declared_original_"+name;"";"unavailable"]; end
source.Status=["FAIL";"PASS";"NA"];
source.ChannelExecutionConfigurationEpoch=["physical-epoch-17";"";"physical-epoch-19"];
clockFields=["ChannelExecutionStartSample","ChannelExecutionEndSampleExclusive", ...
    "ChannelExecutionSampleRateHz","ChannelExecutionSegmentCount","ChannelExecutionDesiredSegmentCount"];
for name=clockFields, source.(name)=[120;NaN;0]; end
source.ChannelExecutionEndSampleExclusive=[240;NaN;0];
source.ChannelExecutionSampleRateHz=[7.68e6;NaN;15.36e6];
source.PrivateTransmitterOracle=[999;888;777];
expected=string(source.Properties.VariableNames);
expected=expected(expected~="PrivateTransmitterOracle");
base=struct('pdsch_table',source,'pusch_table',source,'pdcch_dci_table',source);
before=base; beforeRNG=rng;
published=sixgr.truth.buildLLSPublicOutputTables(base,contract,meta);
assert(isequaln(base,before) && isequal(rng,beforeRNG), ...
    'test:PublicProjectionMutatedSource','Projection must not mutate source evidence or execute stochastic work.');
families=["pdsch_runtime_event_table","pusch_runtime_event_table","pdcch_dci_public_table"];
for family=families
    out=published.(family);
    assert(height(out)==height(source) && isequal(out.Slot,source.Slot), ...
        'test:PublicProjectionPopulation','Preserve the exact source row population and order.');
    for name=expected
        assert(ismember(name,string(out.Properties.VariableNames)) && isequaln(out.(name),source.(name)), ...
            'test:PublicReceiverAuthorityLost','%s changed or dropped receiver authority %s.',family,name);
    end
    assert(~ismember('PrivateTransmitterOracle',out.Properties.VariableNames), ...
        'test:PublicProjectionPrivateLeak','The bounded evidence projection must not copy arbitrary private columns.');
end

% Row presence, generic success and configured/finite metrics cannot create
% optional receiver authority that the source never supplied.
missing=table([9;3],[true;false],[0;1],[40;40],[1024;1024], ...
    'VariableNames',{'Slot','CRCApplicable','CRCPass','ConfiguredSNR_dB','TBSize_bits'});
base=struct('pdsch_table',missing,'pusch_table',missing,'pdcch_dci_table',missing);
published=sixgr.truth.buildLLSPublicOutputTables(base,contract,meta);
optional=["PDCCHReceiverDecodeOk","PDCCHDataAdmissionOk","PDCCHTCIAdmissionStatus", ...
    "CountsTowardCoverage","PartialRowFlag","FinalizedFlag", ...
    "RuntimeMaterializationStatus","RuntimeEvidenceSource", ...
    "DetectionApplicable","MeasurementAttemptKnown","MeasurementDefinition", ...
    "ChannelExecutionEvidenceAvailable","ChannelExecutionConfigurationEpoch"];
for family=families
    out=published.(family);
    assert(height(out)==height(missing) && isequal(out.Slot,missing.Slot));
    assert(~any(ismember(optional,string(out.Properties.VariableNames))), ...
        'test:PublicReceiverAuthorityInvented','Missing optional producer authority must remain absent.');
end
empty=sixgr.truth.buildLLSPublicOutputTables(struct(),contract,meta);
for family=families
    assert(isempty(empty.(family)), 'test:PublicProjectionPlaceholder','Do not add a placeholder execution row.');
end
fprintf('LLS_RECEIVER_AUTHORITY_PUBLIC_PROJECTION_PASS families=3 rows=3 missing_and_empty=1 physical_qualification=0\n');
ok=true;
end
