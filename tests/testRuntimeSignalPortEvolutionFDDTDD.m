function ok = testRuntimeSignalPortEvolutionFDDTDD()
%TESTRUNTIMESIGNALPORTEVOLUTIONFDDTDD One channel, changing active signals.
%
% Initial access uses a one-port UL common waveform.  Later SRS/PUSCH can
% use a different configured number of logical ports, but must retain the
% same physical array and channel realization.  Duplexing changes legal
% occasions only; this antenna/channel invariant is common to FDD and TDD.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
scenarioPaths = [ ...
    fullfile("simulator", "configs", "scenarios", ...
        "lls_causal_access_to_data_wiring.yaml"), ...
    fullfile("simulator", "configs", "scenarios", ...
        "lls_causal_access_to_data_wiring_tdd.yaml")];
expectedDuplex = ["FDD", "TDD"];
expectedSRSPorts = [2, 1];

for profileIdx = 1:numel(scenarioPaths)
    scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPaths(profileIdx));
    cfg = sixgr.config.normalizeConfig( ...
        sixgr.lls6g.buildInternalConfig(scfg, string(tempname)));
    assert(upper(string(sixgr.phy.frame.resolveDuplexMode(cfg))) == ...
        expectedDuplex(profileIdx));

    ueArray = sixgr.rf.AntennaArrayFactory.build(cfg, "ue");
    bsArray = sixgr.rf.AntennaArrayFactory.build(cfg, "bs");
    ueMeta = ueArray;
    bsMeta = bsArray;
    physicalUEElements = double(ueArray.NumElements);
    physicalBSBranches = double(bsArray.NumElements);
    assert(physicalUEElements >= expectedSRSPorts(profileIdx));

    txInfo = struct("OFDM", struct("SampleRate", 7.68e6));
    linkKey = sixgr.channel.ChannelFactory.runtimeChannelKey( ...
        cfg, "UL", "UEIndex", 1, "ServingCell", 1);
    state = sixgr.channel.ChannelFactory.createRuntimeChannelState( ...
        cfg, "UL", "LinkKey", linkKey, "UEIndex", 1, ...
        "ServingCell", 1);

    accessWaveform = complex(ones(128, 1), zeros(128, 1));
    [accessArray, accessMeta] = ...
        sixgr.rf.AntennaArrayFactory.logicalPortView( ...
        ueArray, ueMeta, 1, "test_access_active_waveform_ports");
    state = sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
        state, cfg, accessWaveform, txInfo, ...
        "NumTxAnt", physicalUEElements, ...
        "NumRxAnt", physicalBSBranches, ...
        "TransmitAntennaRuntime", accessArray, ...
        "ReceiveAntennaRuntime", bsArray, ...
        "TransmitAntennaMeta", accessMeta, ...
        "ReceiveAntennaMeta", bsMeta);
    initialSeed = double(state.Seed);
    initialResetCount = double(state.ResetCount);
    assert(double(state.ExternalLogicalTxPorts) == 1 && ...
        double(state.PhysicalChannelTxElements) == physicalUEElements && ...
        logical(state.ElementExpansionApplied));

    activePorts = expectedSRSPorts(profileIdx);
    srsWaveform = complex(ones(128, activePorts), ...
        zeros(128, activePorts));
    [srsArray, srsMeta] = ...
        sixgr.rf.AntennaArrayFactory.logicalPortView( ...
        ueArray, ueMeta, activePorts, ...
        "test_srs_active_waveform_ports");
    state = sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
        state, cfg, srsWaveform, txInfo, ...
        "NumTxAnt", physicalUEElements, ...
        "NumRxAnt", physicalBSBranches, ...
        "TransmitAntennaRuntime", srsArray, ...
        "ReceiveAntennaRuntime", bsArray, ...
        "TransmitAntennaMeta", srsMeta, ...
        "ReceiveAntennaMeta", bsMeta);
    [received, replay, state] = ...
        sixgr.channel.ChannelFactory.applyRuntimeChannelState( ...
        state, srsWaveform);

    assert(double(state.Seed) == initialSeed && ...
        double(state.ResetCount) == initialResetCount, ...
        "%s changed the channel realization while changing active ports.", ...
        expectedDuplex(profileIdx));
    assert(double(state.ExternalLogicalTxPorts) == activePorts && ...
        double(replay.RuntimeChannelActiveTxPorts) == activePorts && ...
        double(state.PhysicalChannelTxElements) == physicalUEElements, ...
        "%s conflated active logical ports with physical elements.", ...
        expectedDuplex(profileIdx));
    assert(size(received, 2) == physicalBSBranches && ...
        all(isfinite(real(received(:)))) && ...
        all(isfinite(imag(received(:)))), ...
        "%s did not produce a finite receive waveform on every BS branch.", ...
        expectedDuplex(profileIdx));
end

ok = true;
fprintf("[PASS] testRuntimeSignalPortEvolutionFDDTDD shared FDD/TDD port evolution retained.\n");
end
