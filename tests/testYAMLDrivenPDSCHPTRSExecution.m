function ok = testYAMLDrivenPDSCHPTRSExecution()
%TESTYAMLDRIVENPDSCHPTRSEXECUTION Prove YAML controls real PDSCH PT-RS.

setup6GRSimToolkit("Verbose", false);
scenarioRoot = fullfile(pwd, "simulator", "configs", "scenarios");
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    scenarioRoot, "webgui_sinr_sweep_64x4_mu_mimo_repair_slice.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scenario, tempdir);
assert(logical(scenario.get("reference_signals.ptrs_enabled")) && ...
    cfg.phy.pdsch.enablePTRS, ...
    "The enabled YAML PT-RS flag must reach the production PDSCH config.");

grant = struct( ...
    "Direction", "DL", "Frame", 1, "Slot", 6, ...
    "RNTI", 1, "UEIndex", 1, "ServingCell", 1, ...
    "PRBSet", 0:11, "SymbolAllocation", [0 14], ...
    "Modulation", "QPSK", "NumLayers", 2, "Layers", 2, ...
    "TargetCodeRate", 0.1884765625, "MCSIndex", 1, "MCS", 1, ...
    "MCSTable", "qam256_table2", "XOverhead", 0, ...
    "GrantContextId", "phase19_yaml_pdsch_ptrs_regression", ...
    "PrecodingActive", true);
[ptrsEnabled, ptrsPorts, ptrsSource] = ...
    sixgr.phy.grant.resolveScheduledPTRSPortSet( ...
    cfg, "DL", 0:1, grant);
grant.PTRSEnabled = ptrsEnabled;
grant.PTRSPortSet = ptrsPorts;
grant.PTRSPortSetSource = ptrsSource;
grant.DMRSPortSet = 0:1;
grant.K0 = 0;
cfg = sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg, grant.Slot);
grant.ControlDecodeOk = true;
grant.PDCCHGrantBindingRequired = true;
grant.PDCCHGrantBindingOk = true;
grant.PDCCHGrantBindingStatus = "pass";
grant.PDCCHGrantDCIId = "phase19-yaml-pdsch-ptrs-dci";
grant.PDCCHGrantDCIFieldsHash = "phase19_yaml_pdsch_ptrs_binding";
grant.PDCCHGrantFieldsHash = grant.PDCCHGrantDCIFieldsHash;
grant.DCICrcPass = true;
grant.PDCCHPayloadMatch = true;
grant.PDCCHCausalGrantDecodeOk = true;
grant.PDCCHMissedDetection = false;
grant.PDCCHFalseAlarm = false;
grant.GrantValid = true;
grant.PDCCHBlindSearchEnabled = true;
grant.PDCCHREGMappingAvailable = true;
grant.PDCCHControlEvidenceSource = "pdcch_waveform_dci_crc_and_payload_match";
grant.ControlDecodeSource = grant.PDCCHControlEvidenceSource;

% Let exact resource accounting derive the legal transport-block size from
% the YAML-driven DM-RS/PT-RS allocation; do not inject a made-up TBS.
carrier = sixgr.phy.grid.makeCarrier(cfg);
[pdschInd, pdschInfo, pdsch] = sixgr.phy.grid.allocREsPDSCH( ...
    carrier, cfg, "PRBSet", grant.PRBSet, ...
    "SymbolAllocation", grant.SymbolAllocation, ...
    "NumLayers", grant.NumLayers, "Modulation", grant.Modulation, ...
    "RNTI", grant.RNTI, "NID", carrier.NCellID, ...
    "MappingType", cfg.phy.pdsch.mappingType);
acct = sixgr.phy.resource.computeResourceAccounting( ...
    "PDSCH", carrier, pdsch, "ChannelIndices", pdschInd, ...
    "AllocationInfo", pdschInfo, "IndexBase", "1based", ...
    "TargetCodeRate", grant.TargetCodeRate, "XOverhead", grant.XOverhead);
grant.NREPerPRB = acct.NREPerPRBForTBS;
grant.TBSBits = double(nrTBS(pdsch.Modulation, pdsch.NumLayers, ...
    numel(pdsch.PRBSet), acct.NREPerPRBForTBS, ...
    grant.TargetCodeRate, grant.XOverhead));

phyGrant = sixgr.phy.grant.freezePHYGrant( ...
    cfg, "DL", grant, "SNR_dB", 20, "Frame", 1, "Slot", 6);
[tx, ~] = sixgr.phy.dl.PDSCH_Tx( ...
    cfg, "PHYGrant", phyGrant, "SchedulerGrantContext", grant, ...
    "CompactOutput", true);
[metrics, ~] = sixgr.link.deriveModulationTrackingMetrics( ...
    tx, struct(), cfg, "DL");

assert(logical(phyGrant.CodingLayout.PTRSEnabled), ...
    "The frozen DL coding layout must retain YAML-enabled PT-RS.");
assert(isequal(double(phyGrant.CodingLayout.PTRSPortSet), 0), ...
    "The rank-2 YAML policy must associate PDSCH PT-RS with the first scheduled DM-RS port.");
assert(~isempty(tx.PTRSIndices) && ~isempty(tx.PTRSSymbols) && ...
    ~isempty(tx.PTRSAntennaIndices) && ~isempty(tx.PTRSAntennaSymbols), ...
    "The scheduler-truth PDSCH waveform must materialize native and antenna-domain PT-RS.");
assert(double(metrics.DMRSRECount) > 0 && double(metrics.PTRSRECount) > 0, ...
    "DL modulation-tracking evidence must report positive DM-RS and PT-RS RE counts.");
assert(logical(tx.ResourceAccounting.DisjointMasks), ...
    "PDSCH data, DM-RS and PT-RS masks must remain disjoint.");
assert(size(tx.Waveform, 2) == 64, ...
    "The YAML-enabled PDSCH allocation must propagate through all 64 configured gNB elements; observed %d.", ...
    size(tx.Waveform, 2));

contradictoryPDSCH = tx.PDSCH;
contradictoryPDSCH.EnablePTRS = false;
localAssertThrows(@() sixgr.phy.dl.PDSCH_Tx( ...
    cfg, "PDSCH", contradictoryPDSCH, "CompactOutput", true), ...
    "sixgr:config:YAMLFeatureExecutionMismatch");

ok = true;
end

function localAssertThrows(fcn, identifier)
didThrow = false;
try
    fcn();
catch ME
    didThrow = strcmp(string(ME.identifier), string(identifier));
    if ~didThrow
        rethrow(ME);
    end
end
assert(didThrow, "Expected typed error %s.", identifier);
end
