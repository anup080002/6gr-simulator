function ok = testPDCCHDetectionConfidenceSweep()
%TESTPDCCHDETECTIONCONFIDENCESWEEP Fixed-sample detection interval guard.

setup6GRSimToolkit("Verbose", false);
b = pdcchStrictAnchorResult();
T = b.Result.ArtifactTables.pdcch_low_snr_sweep;
required = ["NumTrials","NumDetected","NumCrcPass","DetectionCILower", ...
    "DetectionCIUpper","CrcPassCILower","CrcPassCIUpper", ...
    "ConfidenceLevel","IntervalMethod","EvidenceUnit"];
assert(all(ismember(required,string(T.Properties.VariableNames))), ...
    "PDCCH detection characterization must export counts and confidence intervals.");
assert(all(double(T.DetectionCILower) <= double(T.DetectionProbability)) && ...
    all(double(T.DetectionCIUpper) >= double(T.DetectionProbability)), ...
    "PDCCH detection intervals must contain their point estimates.");
assert(all(double(T.CrcPassCILower) <= double(T.CrcPassProbability)) && ...
    all(double(T.CrcPassCIUpper) >= double(T.CrcPassProbability)), ...
    "PDCCH CRC-pass intervals must contain their point estimates.");
ok = true;
end
