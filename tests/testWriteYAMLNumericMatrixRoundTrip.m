function ok = testWriteYAMLNumericMatrixRoundTrip()
%TESTWRITEYAMLNUMERICMATRIXROUNDTRIP Preserve row/column semantics in YAML.

root = string(tempname);
mkdir(root);
cleanup = onCleanup(@() rmdir(root, "s")); %#ok<NASGU>
pathValue = fullfile(root, "matrix_roundtrip.yaml");

dlAllocations = [ ...
    (0:15).', ...
    [2;2;3;2;2;9;4;5;5;9;12;1;1;2;4;8], ...
    [12;10;11;9;7;4;4;7;2;2;2;13;6;4;7;4], ...
    4*ones(16,1)];
logicalMask = logical([1 0 1; 0 1 0]);
source = struct("control", struct("dl_time_domain_allocations", ...
    dlAllocations, "logical_mask", logicalMask));

sixgr.lls6g.config.writeYAML(pathValue, source);
decoded = sixgr.lls6g.config.readConfigFile(pathValue);

assert(isequal(size(decoded.control.dl_time_domain_allocations), [16 4]) && ...
    isequal(double(decoded.control.dl_time_domain_allocations), dlAllocations), ...
    "Numeric allocation-table row and column semantics changed during YAML round trip.");
assert(isequal(size(decoded.control.logical_mask), [2 3]) && ...
    isequal(logical(decoded.control.logical_mask), logicalMask), ...
    "Logical matrix row and column semantics changed during YAML round trip.");

text = string(fileread(pathValue));
assert(contains(text, "[[0, 2, 12, 4], [1, 2, 10, 4]") && ...
    contains(text, "[[true, false, true], [false, true, false]]"), ...
    "YAML matrix serialization did not emit explicit nested row sequences.");

ok = true;
end
