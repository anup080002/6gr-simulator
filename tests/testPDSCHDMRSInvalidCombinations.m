function ok = testPDSCHDMRSInvalidCombinations()
%TESTPDSCHDMRSINVALIDCOMBINATIONS Require stable typed pre-waveform errors.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
base = struct( ...
    "MappingType", "A", "DMRSLength", 1, ...
    "PDSCHStartSymbol", 0, "PDSCHDurationLd", 12, ...
    "DMRSTypeAPosition", 2, "DMRSAdditionalPosition", 1, ...
    "DMRSConfigurationType", 1, ...
    "DMRSMultiplexing", "basic", ...
    "DMRSPortSet", 0, "NumLayers", 1, ...
    "NumCDMGroupsWithoutData", 1);

localChangedError(base, "DMRSTypeAPosition", 1, ...
    "sixgr:pdsch:InvalidDMRSTypeAPosition");
localChangedError(base, "DMRSConfigurationType", 3, ...
    "sixgr:pdsch:InvalidDMRSConfigurationType");
localChangedError(base, "DMRSLength", 3, ...
    "sixgr:pdsch:InvalidDMRSLength");
double = base;
double.DMRSLength = 2;
double.DMRSAdditionalPosition = 2;
localAssertError(@() sixgr.pdsch.PDSCHDMRSValidator. ...
    validateConfiguration(double), ...
    "sixgr:pdsch:UnsupportedDMRSPositionCombination");
gapPort = base;
gapPort.DMRSMultiplexing = "enhanced";
gapPort.DMRSPortSet = 4;
localAssertError(@() sixgr.pdsch.PDSCHDMRSValidator. ...
    validateConfiguration(gapPort), ...
    "sixgr:pdsch:DMRSPortUnsupportedForConfiguration");
badGroups = base;
badGroups.NumCDMGroupsWithoutData = 3;
localAssertError(@() sixgr.pdsch.PDSCHDMRSValidator. ...
    validateConfiguration(badGroups), ...
    "sixgr:pdsch:InvalidNumCDMGroupsWithoutData");
wrongLayers = base;
wrongLayers.DMRSPortSet = [0 1];
localAssertError(@() sixgr.pdsch.PDSCHDMRSValidator. ...
    validateConfiguration(wrongLayers), ...
    "sixgr:pdsch:DMRSPortLayerMismatch");
ok = true;
end

function localChangedError(base, field, value, id)
changed = base;
changed.(field) = value;
localAssertError(@() sixgr.pdsch.PDSCHDMRSValidator. ...
    validateConfiguration(changed), id);
end

function localAssertError(fn, expectedID)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(expectedID), ...
        "Observed %s, expected %s.", ME.identifier, expectedID);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.", expectedID);
end
