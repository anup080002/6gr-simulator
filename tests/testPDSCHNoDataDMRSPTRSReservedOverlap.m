function ok = testPDSCHNoDataDMRSPTRSReservedOverlap()
%TESTPDSCHNODATADMRSPTRSRESERVEDOVERLAP Reject every illegal overlap.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
map = sixgr.pdsch.PDSCHResourceOwnershipMap( ...
    0:47, struct("SSB", 0:5));
validContext = localContext({6:11}, {12:13});
plan = sixgr.pdsch.PDSCHResourcePlan(map, validContext);
assert(isempty(intersect(plan.DataIndices, 0:13)) && ...
    plan.ExactDataRECount == 34, ...
    "Valid DM-RS/PT-RS/reserved sets were not excluded before data.");

reservedCollision = localContext({0}, {12});
localAssertError(@() sixgr.pdsch.PDSCHResourcePlan( ...
    map, reservedCollision), ...
    "sixgr:pdsch:DataDMRSPTRSReservedCollision");
referenceCollision = localContext({6}, {6});
localAssertError(@() sixgr.pdsch.PDSCHResourcePlan( ...
    map, referenceCollision), ...
    "sixgr:pdsch:DataDMRSPTRSReservedCollision");
outside = localContext({48}, {12});
localAssertError(@() sixgr.pdsch.PDSCHResourcePlan(map, outside), ...
    "sixgr:pdsch:ReferenceREOutsideAllocation");
noData = localContext({6:47}, cell(1, 0));
localAssertError(@() sixgr.pdsch.PDSCHResourcePlan(map, noData), ...
    "sixgr:pdsch:NoPDSCHDataREAfterReferenceSignals");
ok = true;
end

function context = localContext(dmrs, ptrs)
context = struct( ...
    "PRBSet", 0, "SymbolAllocation", [0 4], ...
    "GridNumPRB", 1, ...
    "GridSymbolsPerSlot",14,"BWPStartPRB",0,"AbsoluteSlot",0, ...
    "UnavailableIndices",zeros(1,0), ...
    "DMRSIndicesPerPort", {dmrs}, ...
    "PTRSIndicesPerPort", {ptrs}, ...
    "DMRSLogicalPortSet",0:(numel(dmrs)-1), ...
    "PTRSLogicalPortSet",0:(numel(ptrs)-1), ...
    "LayerCountPerCodeword", 1, ...
    "QmPerCodeword", 2, ...
    "CodeBlockCountPerCodeword", 1);
end

function localAssertError(fn, expectedID)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(expectedID), ...
        "Observed %s, expected %s.", ME.identifier, expectedID);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.", expectedID);
end
