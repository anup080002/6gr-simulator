function ok = interferenceCampaignAcceptance()
%INTERFERENCECAMPAIGNACCEPTANCE Shared-slot interference and seed campaign anchors.

nSamples = 64;
nRx = 2;
t = (0:nSamples-1).';
desired = complex(ones(nSamples, nRx), zeros(nSamples, nRx));
a = [exp(1j*2*pi*t/13), 0.5*exp(1j*2*pi*t/17)] * 1e-3;
b = [-0.25*exp(1j*2*pi*t/19), 0.75*exp(1j*2*pi*t/23)] * 1e-3;
bundle = [localContribution("cell2", a); localContribution("cell3", b)];
replay = struct("ServingRxPower_dBm", -50, "ServingRSRPSource", "release_anchor", "SampleRate_Hz", 30.72e6);

[iwf, meta] = sixgr.link.synthesizeInterferenceWaveform("DL", desired, replay, bundle);
expected = a + b;
assert(max(abs(iwf(:) - expected(:))) < 1e-15, ...
    "Shared-slot interference must equal the exact sample sum of stored contributions.");
assert(logical(meta.ContributionTensorAvailable) && size(meta.ContributionTensor, 3) == 2, ...
    "Shared-slot interference must retain per-source contribution tensors.");
assert(max(abs(sum(meta.ContributionTensor, 3) - expected), [], "all") < 1e-15, ...
    "Contribution tensor planes must reconstruct the composite interference.");
assert(~logical(meta.TxRegenerationUsed) && ~logical(meta.PostChannelNormalizationApplied) && ...
    ~logical(meta.RandomPhaseApplied), ...
    "Interference synthesis must not regenerate Tx, renormalize post-channel, or apply random phase.");

weaker = bundle(1);
weaker.SharedSlotContributionWaveform = a .* sqrt(0.5);
[~, strongMeta] = sixgr.link.synthesizeInterferenceWaveform("DL", desired, replay, bundle(1));
[~, weakMeta] = sixgr.link.synthesizeInterferenceWaveform("DL", desired, replay, weaker);
assert(abs((double(weakMeta.AggregatedRxPower_dBm) - double(strongMeta.AggregatedRxPower_dBm)) + 3.01029995664) < 1e-9, ...
    "sqrt(0.5) contribution amplitude must reduce measured interference power by 3.0103 dB.");

seedBase = 94123;
pointSeeds = arrayfun(@(idx) double(mod(seedBase + idx * 1000003 + 17 * 9176, 2147483647)), 1:3);
assert(numel(unique(pointSeeds)) == 3 && isequal(pointSeeds, pointSeeds), ...
    "Release campaign seed hierarchy must assign deterministic unique point seeds.");
ok = true;
end

function entry = localContribution(sourceId, waveform)
entry = struct( ...
    "InterferenceMode", "full_per_link_channel_waveform_sum", ...
    "SourceId", char(string(sourceId)), ...
    "SharedSlotContributionWaveform", waveform, ...
    "ContributionSampleRate_Hz", 30.72e6, ...
    "ChannelObjectSource", "release_acceptance_channel", ...
    "ChannelObjectClass", "sample_domain_contribution", ...
    "ChannelArrayHandlingStatus", "shared_slot_receiver_contribution", ...
    "ChannelGeometryCouplingLevel", "sample_exact", ...
    "ChannelUsesSameRuntimeAntennaAssumptions", true, ...
    "GrantSnapshot", struct("PrecoderSource", "release_anchor", ...
    "PrecodingMode", "sample_domain", "AppliedBeamIndexSet", "1", ...
    "BeamformingApplied", true, "ExplicitBeamWeightsApplied", true, ...
    "TransformPrecodingApplied", false));
end
