function [ok,result]=testOriginalGrantProvenanceTypes()
% Declared metadata fixtures through real consumers; no PHY qualification.
setup6GRSimToolkit('Verbose',false);
folder=fullfile(pwd,'results','validation','original_grant_provenance_types', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
assert(~isfolder(folder),'Never overwrite retained evidence.');
sixgr.util.ensureFolder(folder);
fields=["CQIProvenance","SchedulerCQISource","GrantContextId","FrozenGrantContextId", ...
    "MCSSelectionSource","MCSValueStatus","MCSIndexAuthority", ...
    "GrantOperatingPointSource","LinkAdaptationDecisionReason"];
scfg=struct('ScenarioID',"declared_invalid_grant_provenance",'ConfigHash',"declared_not_PHY");
scfg.simulation.random_seed=1;
scfg.frequency=struct('center_frequency_hz',4e9,'bandwidth_hz',100e6);
scfg.frame.scs_khz=30;
cfg=struct('frequency',scfg.frequency,'run',struct('runTag',"declared_not_PHY"));
hashes=strings(numel(fields),1);
for k=1:numel(fields)
    runFolder=fullfile(folder,fields(k));
    inputDir=fullfile(runFolder,'packet_flow','csv');
    sixgr.util.ensureFolder(inputDir);
    direction="DL"; if mod(k,2)==0, direction="UL"; end
    g=table(direction,1,17,1,4660,1,"declared_fixture",false,1,10,7, ...
        "qam64_table1","table1",0,10,2,12,176, ...
        'VariableNames',{'Direction','Frame','Slot','UEIndex','RNTI','ServingCell', ...
        'GrantReason','IsRetransmission','HarqID','CQIUsed','MCSIndex', ...
        'MCSTable','CQITable','PRBStart','PRBCount','SymbolStart','NumSymbols','TBSBits'});
    for name=fields, g.(name)="declared_original_"+name; end
    g.(fields(k))=1; % Original finite numeric, not string "1".
    path=fullfile(inputDir,"live_"+lower(direction)+"_scheduler_grants.csv");
    sixgr.util.csvWriteTable(path,g,'PreserveSchema',true,'RoundTripNumericText',true);
    imported=sixgr.util.csvReadTable(path,'TextType','string');
    assert(isnumeric(imported.(fields(k)))&&isequal(imported.(fields(k)),1), ...
        'Negative must exercise actual numeric CSV inference for %s.',fields(k));
    hashes(k)=sixgr.util.sha256File(path);
    reject(@()sixgr.truth.exportLLSOutputCoverageArtifacts(runFolder,scfg,cfg), ...
        'sixgr:report:MCSCQIProvenanceType');
    assert(hashes(k)==string(sixgr.util.sha256File(path)), ...
        'Rejecting malformed provenance must preserve original evidence.');
end

% Direct actual public consumer: no expensive successful full-export repeat.
source=table((1:5).',[7;31;7.5;7;7],[7;31;7.5;31;7], ...
    ["not_an_installed_table";"qam64_table1";"qam64_table1";"qam64_table1";"qam64_table1"], ...
    'VariableNames',{'slot','mcs_selected','cqi_derived_mcs','mcs_table'});
source.mcs_selection_source=repmat("declared_fixed_configuration",5,1);
before=source; beforeRNG=rng;
meta=struct('logical_run_id',"declared_profile_boundary",'run_id',1);
tables=sixgr.truth.buildLLSPublicOutputTables( ...
    struct('table_mcs_tbs_evolution',source),sixgr.truth.llsOutputContract(),meta);
p=tables.mcs_cqi_decision_trace_table;
assert(height(p)==5 && all(p.MCSMismatchStatus(1:4)=="unavailable"), ...
    'Unknown/reserved/nonintegral profiles cannot become same-index matches.');
assert(all(isnan(p.SelectedSpectralEfficiency(1:3))) && ...
    all(isnan(p.BoundSpectralEfficiency(1:4))), ...
    'Unavailable spectral efficiencies must remain unavailable.');
assert(isfinite(p.SelectedSpectralEfficiency(4)) && ...
    p.MCSMismatchStatus(5)=="match" && ...
    isfinite(p.SelectedSpectralEfficiency(5)) && isfinite(p.BoundSpectralEfficiency(5)), ...
    'Valid selected SE is retained independently of an unavailable bound.');
assert(isequaln(source,before)&&isequaln(rng,beforeRNG));
sixgr.util.csvWriteTable(fullfile(folder,'public_invalid_profile_projection.csv'),p, ...
    'PreserveSchema',true,'RoundTripNumericText',true);
result=struct('EvidenceRoot',string(folder),'OriginalSHA256',hashes, ...
    'RejectedOriginalNumericFields',fields,'PublicProfileCases',5, ...
    'PHYExecutions',0,'Scope',"declared_metadata_original_CSV_rejection_and_public_projection", ...
    'StatisticalQualification',false);
ok=true;
fprintf('ORIGINAL_GRANT_PROVENANCE_PASS numeric_negatives=%d public_profile_cases=5 PHY_executions=0 root=%s\n', ...
    numel(fields),folder);
end

function reject(fn,id)
try, fn(); catch cause
    assert(string(cause.identifier)==id,'Expected %s, received %s: %s',id,cause.identifier,cause.message);
    return;
end
error('test:MissingOriginalGrantProvenanceGuard','Expected %s.',id);
end
