function ok = testGrantTraceRuntimeStateIdentity()
% Regression for the first post-access grant in a coupled sweep: grant
% tracing must consume the explicit runtime state, not an undefined free
% variable.
state = struct("CurrentSweepPointIndex", 3, "CurrentSNR_dB", 20, ...
    "CurrentSlot", 16, "CurrentFrame", 1, ...
    "DLGrantTraceTable", table(), "ULGrantTraceTable", table());
grant = struct("PRBSet", 0:9, "SymbolAllocation", [2 10], ...
    "RNTI", 1001, "ServingCell", 1, "TBSBits", 1024, "TBSBytes", 128, ...
    "MCSIndex", 6, "MCSTable", "qam256", "CQITable", "table1", ...
    "Modulation", "16QAM", "TargetCodeRate", 0.48, "NumLayers", 2, ...
    "HARQ", struct("HarqID", 0, "NDI", 1, "RV", 0, ...
    "IsRetransmission", false));
state = sixgr.truth.CoupledTruthRuntime.appendGrantTraceRuntime( ...
    state, grant, "DL", struct("CQI", 7, "RI", 2));
assert(height(state.DLGrantTraceTable) == 1);
row = table2struct(state.DLGrantTraceTable(1, :));
assert(double(row.SweepPointIndex) == 3);
assert(double(row.ConfiguredSNR_dB) == 20);
assert(double(row.Slot) == 16 && double(row.Frame) == 1);
assert(double(row.TBSBits) == 1024 && double(row.TBSBytes) == 128);
assert(double(row.NumLayers) == 2 && double(row.Rank) == 2);
ok = true;
end
