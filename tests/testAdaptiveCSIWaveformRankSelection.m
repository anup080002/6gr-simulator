function ok=testAdaptiveCSIWaveformRankSelection()
% Actual full-band CSI-RS waveform/receiver, with declared static test
% channels. Decoded-report API delivery is a component boundary fixture,
% NOT physical PUCCH, access, CDL/RF qualification or a production result.
setup6GRSimToolkit('Verbose',false);
source=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_gate.yaml');
cfg=sixgr.lls6g.buildInternalConfig(source,tempname);
assert(cfg.phy.pdsch.maxLayers==4 && cfg.phy.linkAdaptation.rankIncreaseConfirmationReports==2);
policy=sixgr.mimo.resolveRankPolicy(cfg);
assert(policy.AdaptiveRank && ~policy.FixedRankAnchor);
cfg.channel.model='AWGN'; cfg.channel.awgnOnly=true;
cfg.phy.rx.cfoCorrectionEnabled=true;
cfg.phy.impairments.cfoEstimationMethod='cyclic_prefix';
cfg.lls6g.runtimePowerContext=struct('WaveformAmplitudeUnit','normalized_unit_es', ...
    'PhysicalDevicePowerClaim',false);
cfg.phy.csi.rankDomain=[1 2 4];
cfg.phy.csi.reportConfiguration.AllowedRanks=[1 2 4];
carrier=nrCarrierConfig('SubcarrierSpacing',30,'NSizeGrid',273, ...
    'NCellID',cfg.phy.carrier.NCellID,'NSlot',5);
folder=fullfile(pwd,'results','lls','adaptive_csi_component', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(folder);
rows=table();
for channelRank=[1 2 4]
    state=struct('CfgMobility',cfg,'NumUsers',1,'DLSchedulers',{{}}, ...
        'ULSchedulers',{{}},'DLLinkAdaptationState',{{struct()}}, ...
        'ULLinkAdaptationState',{{struct()}},'SlotDuration_s',.0005);
    for repetition=1:2
        slot=6+20*(repetition-1);
        current=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,slot);
        current.runtime.currentSlot=slot;
        current.lls6g.runtime.AbsoluteSlotIndex0=slot-1;
        current.lls6g.userContext=struct('RuntimeUEIndex',1,'RuntimeCurrentSlot',slot);
        carrier.NSlot=slot-1;
        physical=sixgr.phy.refsig.materializeCSIRSPhysicalGrid( ...
            carrier,current,'WaveformPortCount',64);
        assert(physical.Event.Transmitted && physical.Event.NumResources==8 && ...
            size(physical.Grid,3)==64);
        [waveform,ofdm]=nrOFDMModulate(carrier,physical.Grid,'Windowing',0);
        basis=current.phy.csirs.precoderMatrices(:,:,1);
        spectrum=zeros(4,1); spectrum(1:channelRank)=1;
        channel=diag(spectrum)*basis';
        delay=13; guard=1229; frequency=400;
        capture=[zeros(delay,4);waveform*channel.';zeros(guard-delay,4)];
        capture=capture.*exp(2i*pi*frequency*(0:size(capture,1)-1).'/ofdm.SampleRate);
        seed=821910+10*channelRank+repetition;
        capture=sixgr.phy.waveform.addOccupiedREAWGN(capture,carrier,40, ...
            'Seed',seed,'SignalEnergyPerOccupiedRE',1);
        % Only received samples/installed references reach the receiver.
        received=sixgr.phy.refsig.receiveCSIRSWaveform( ...
            carrier,current,capture,capture,[0 guard],struct());
        [report,detail]=sixgr.phy.refsig.computeCSIRSFeedback(carrier,current,received);
        assert(report.RI==channelRank && ~report.ConfiguredOracleUsed && ...
            ~detail.PDSCHDecodeAttempted && ~detail.DCIConsumed, ...
            'test:AdaptiveCSIWaveformRank','Rank must follow the measured test channel, not configured maximum four.');
        wire=sixgr.phy.mimo.CSIReportConfiguration( ...
            current.phy.csi.reportConfiguration,current.phy.csi.reportConfiguration.Epoch);
        decoded=wire.decode(report.CSIPart1Bits,report.CSIPart2Bits);
        assert(decoded.RI==report.RI && decoded.PMI==report.PMI && decoded.CRI==report.CRI);
        delivered=struct('SourceSignal',"CSI-RS",'CQI',decoded.CQI_CW0,'RI',decoded.RI, ...
            'PMI',decoded.PMI,'CRI',decoded.CRI,'SINR_dB',NaN,'SourceSlot',slot, ...
            'DueSlot',slot+1,'DeliveredSlot',slot+1,'ServingCell',1, ...
            'ReportIdentity',"physical_csi_report_boundary_"+channelRank+"_"+repetition);
        [state,admitted]=sixgr.truth.CoupledTruthRuntime.applyDeliveredCSIAdaptationRuntime( ...
            state,delivered,1,'DL',struct());
        expected=channelRank;
        if repetition==1 && channelRank>1, expected=1; end
        assert(admitted.SchedulerAcceptedRank==expected && ...
            state.DLLinkAdaptationState{1}.OLLAUpdateCount==0);
        if repetition==2
            assert(~admitted.SchedulerSpatialDecisionDeferred && isfinite(admitted.MCSIndex));
        end
        fprintf('ADAPTIVE_CSI_SYNC channel_rank=%g timing=%g expected=%g initial=%g CFO=%g initial_evidence=%s\n', ...
            channelRank,received.ReceiveTiming.TimingOffsetSamples,delay, ...
            received.ReceiveTiming.InitialTimingOffsetSamples, ...
            received.ReceiverTrackingCorrection.EstimatedCFO_Hz, ...
            jsonencode(received.ReceiverTrackingCorrection.InitialReceiveTiming));
        save(fullfile(folder,sprintf('channel%d_report%d.mat',channelRank,repetition)), ...
            'current','carrier','capture','channel','seed','received','report','delivered','admitted','-v7.3');
        assert(received.ReceiveTiming.TimingOffsetSamples==delay && ...
            ~received.ReceiveTiming.OracleTimingUsed, ...
            'test:AdaptiveCSITiming','Measured offset %g differs from injected %g; inspect %s.', ...
            received.ReceiveTiming.TimingOffsetSamples,delay,folder);
        % Bounded deterministic operating-point check, not a receiver-wide
        % statistical claim. A sparse-pilot timing alias previously biased
        % CFO by kilohertz despite this high-SNR constant-CFO fixture.
        assert(abs(received.ReceiverTrackingCorrection.EstimatedCFO_Hz-frequency)<50, ...
            'test:AdaptiveCSIFrequency','CFO must be measured after correct received timing alignment.');
        rows=[rows;table(channelRank,slot,seed,report.RI,report.PMI,report.CRI, ...
            report.CQI,admitted.SchedulerAcceptedRank,admitted.MCSIndex, ...
            received.ReceiverTrackingCorrection.EstimatedCFO_Hz, ...
            false,false,'VariableNames',{'DeclaredTestChannelRank','SourceSlot','Seed', ...
            'MeasuredRI','MeasuredPMI','MeasuredCRI','MeasuredCQI','AcceptedRank','MCS', ...
            'EstimatedCFO_Hz','PhysicalUCIDelivery','ScenarioAccepted'})]; %#ok<AGROW>
        fprintf('ADAPTIVE_CSI_PHYSICAL_COMPONENT channel_rank=%g source=%g RI=%g accepted=%g CQI=%g MCS=%g\n', ...
            channelRank,slot,report.RI,admitted.SchedulerAcceptedRank,report.CQI,admitted.MCSIndex);
    end
end
assert(height(rows)==6);
writetable(rows,fullfile(folder,'measured_csi_rank_handoff.csv'));
fprintf('ADAPTIVE_CSI_WAVEFORM_RANK_SELECTION_PASS PRB=273 TX=64 RX=4 beams=8 physical_UCI=0 scenario_accepted=0\n');
ok=true;
end
