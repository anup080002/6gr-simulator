function localAssertIdentifier(fn, expected)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(expected), ...
        "Expected %s, observed %s (%s).", ...
        expected, ME.identifier, ME.message);
    return;
end
error("testDLPDSCHThroughputExecutionContract:MissingError", ...
    "Expected typed error %s.", expected);
end

function localAssertFinalOutcome(result,expectedCodewords)
% Consume the existing execution once; never rerun or reconstruct a decoder.
t=result.TrialTable;
fields=["DLSCHFinalOutcomeAvailable","DLSCHFinalOutcomeStage", ...
    "DLSCHFinalOutcomeJSON","DLSCHFinalOutcomeSHA256", ...
    "DLSCHSuccessfulDecodedBits","DLSCHSuccessfulDecodedBitsScope", ...
    "DLSCHAggregateGoodBitsPolicy"];
assert(height(t)==1&&all(ismember(fields,string(t.Properties.VariableNames)))&& ...
    isequal(t.DLSCHFinalOutcomeAvailable,true)&& ...
    string(t.DLSCHFinalOutcomeStage)=="completed_throughput_decoder_outcome");
token=string(t.DLSCHFinalOutcomeJSON);
assert(isscalar(token)&&strlength(token)>0&& ...
    string(t.DLSCHFinalOutcomeSHA256)==string(sixgr.util.sha256Hex(char(token))));
final=jsondecode(char(token));
assert(string(final.ContractVersion)=="DLSCHFinalDecoderOutcome/v1"&& ...
    string(final.Stage)==string(t.DLSCHFinalOutcomeStage)&& ...
    final.FinalThroughputOutcomeBound&&final.NumCodewords==expectedCodewords&& ...
    final.CodewordIndexBase==0&&final.AdditionalDecoderInvocationCount==0&& ...
    ~final.MACDeliveryQualified&&~final.UniqueTransportBlockIdentityAvailable&& ...
    ~final.StatisticalIndependenceClaimed&& ...
    string(final.PopulationScope)=="one_decoder_attempt_per_explicit_codeword"&& ...
    final.SourceRow.Frame==t.Frame&&final.SourceRow.Slot==t.Slot&& ...
    string(final.SourceRow.ExecutionBackend)==string(t.ExecutionBackend));
if isfield(result,'RX')
    original=result.DLSCHFinalOutcome;
    assert(token==string(jsonencode(original))&&original.FinalThroughputOutcomeBound);
    payloads=result.RX.TransportBlocks;
    if expectedCodewords==1, decoders={result.RX.Decode};
    else, decoders=result.RX.Decode.Codewords; end
else
    original=result.HARQ.FinalCodewordOutcome;
    assert(~original.FinalThroughputOutcomeBound&& ...
        original.Stage=="final_decoder_selection_before_completed_trial_binding");
    payloads=result.HARQ.FinalDecodedTransportBlocks;
    decoders={}; % Legacy runner retains selected payloads/receipts, not RX.
end
assert(iscell(payloads)&&numel(payloads)==expectedCodewords&& ...
    numel(final.Codewords)==expectedCodewords&&numel(original.Codewords)==expectedCodewords);
passes=false(1,expectedCodewords); sizes=zeros(1,expectedCodewords);
for cw=1:expectedCodewords
    if iscell(final.Codewords), word=final.Codewords{cw};
    else, word=final.Codewords(cw); end
    selected=original.Codewords{cw}; bits=int8(payloads{cw}(:));
    assert(word.CodewordIndex==cw-1&&word.CodewordIndexBase==0&& ...
        word.NumCodewords==expectedCodewords&&word.HARQCodewordIndexBase==1&& ...
        logical(word.CRCPass)==selected.CRCPass&&logical(word.CRCError)==~selected.CRCPass&& ...
        word.TransportBlockLengthMatch&&word.TransportBlockSize==numel(bits)&& ...
        word.DecodedTransportBlockLength==numel(bits)&& ...
        string(word.DecodedTransportBlockSHA256)== ...
            string(sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(bits))&& ...
        string(word.CodingPlanID)==selected.CodingPlanID&& ...
        string(word.CodingLayoutHash)==selected.CodingLayoutHash&& ...
        string(word.CombineSignature)==selected.CombineSignature&& ...
        string(word.RateMatchSignature)==selected.RateMatchSignature&& ...
        string(word.SelectedDecoderSource)==selected.SelectedDecoderSource&& ...
        word.AdditionalDecoderInvocationCount==0&&~word.UniqueTransportBlockIdentityAvailable);
    if ~isempty(decoders)
        decoder=decoders{cw};
        assert(isequal(bits,int8(decoder.TransportBlock(:)))&& ...
            logical(word.CRCPass)==decoder.CRCPass&& ...
            string(word.CodingPlanID)==string(decoder.CodingPlanID)&& ...
            string(word.CodingLayoutHash)==string(decoder.CodingLayout.CodingLayoutHash)&& ...
            word.RV==decoder.CodingPlan.RV&& ...
            logical(word.SelectedDecoderUsedCombining)==decoder.HARQCombineInfo.Applied);
    end
    passes(cw)=logical(word.CRCPass); sizes(cw)=numel(bits);
    assert(word.SuccessfulDecodedBits==sizes(cw)*double(passes(cw)));
end
successful=sum(sizes.*double(passes));
assert(isequal(logical(final.CRCPassPerCodeword(:).'),passes)&& ...
    isequal(logical(final.CRCErrorPerCodeword(:).'),~passes)&& ...
    logical(final.CRCPass)==all(passes)&&logical(final.CRCError)==any(~passes)&& ...
    logical(t.CRCPass)==all(passes)&& ...
    final.SuccessfulDecodedBits==successful&&t.DLSCHSuccessfulDecodedBits==successful&& ...
    string(t.DLSCHSuccessfulDecodedBitsScope)=="this_decoder_attempt_not_unique_MAC_delivery"&& ...
    string(t.DLSCHAggregateGoodBitsPolicy)=="all_codewords_CRC_pass_required_existing_throughput_policy"&& ...
    t.GoodBits==sum(sizes)*double(all(passes)));
end
