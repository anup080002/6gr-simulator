function ok = testDLPDSCHThroughputExecutionContract()
%TESTDLPDSCHTHROUGHPUTEXECUTIONCONTRACT Fail closed on ambiguous ownership.
% Actual TX/RX and final-row receipts execute below. The typed connected
% assignment/control context is a declared integration fixture, not a
% decoded-PDCCH, scheduled retry or unique-MAC-delivery qualification.

setup6GRSimToolkit("Verbose", false);
cfg = sixgr.config.defaultConfig();
cfg.phy.pdsch.enable = false;

localAssertIdentifier(@() sixgr.link.runDLPDSCHThroughput( ...
    cfg, "NumFrames", 1), ...
    "sixgr:pdsch:MissingExecutionProfile");

cfgConnected = cfg;
cfgConnected.run.pdschExecutionProfile = "connected_strict";
cfgConnected.run.strictMode = true;
localAssertIdentifier(@() sixgr.link.runDLPDSCHThroughput( ...
    cfgConnected, "NumFrames", 1), ...
    "sixgr:link:StrictCoverageDisabled");
% Assignment ownership is a downstream guard; enable the PHY for that
% distinct test instead of expecting it to bypass disabled strict coverage.
cfgConnected.phy.pdsch.enable = true;
localAssertIdentifier(@() sixgr.link.runDLPDSCHThroughput( ...
    cfgConnected, "NumFrames", 1), ...
    "sixgr:pdsch:MissingSchedulingAssignment");

cfgCalibration = cfg;
cfgCalibration.run.pdschExecutionProfile = "phy_calibration";
localAssertIdentifier(@() sixgr.link.runDLPDSCHThroughput( ...
    cfgCalibration, "NumFrames", 1, ...
    "GrantSnapshot", struct("TBSBits", 128)), ...
    "sixgr:pdsch:CalibrationSchedulerOwnershipForbidden");

cfgConflict = cfgCalibration;
cfgConflict.phy.pdsch.executionProfile = "connected_strict";
localAssertIdentifier(@() sixgr.link.runDLPDSCHThroughput( ...
    cfgConflict, "NumFrames", 1), ...
    "sixgr:pdsch:ExecutionProfileMismatch");

cfgSchedulerTruth = cfg;
cfgSchedulerTruth.run.pdschExecutionProfile = "scheduler_truth";
localAssertIdentifier(@() sixgr.link.runDLPDSCHThroughput( ...
    cfgSchedulerTruth, "NumFrames", 1), ...
    "sixgr:pdsch:MissingSchedulerTruthGrant");

out = sixgr.link.runDLPDSCHThroughput( ...
    cfg, "ExecutionProfile", "phy_calibration", "NumFrames", 1);
assert(out.Ok && out.Skipped);
assert(string(out.ExecutionProfile) == "phy_calibration");
assert(string(out.ExecutionTaxonomy) == "isolated_phy_calibration");
assert(string(out.ExecutionBackend) ...
    == "legacy_pdsch_calibration_facades");
assert(string(out.ApproximationMode) == "none");
assert(string(out.CalibrationProvenance) ...
    == "explicit_phy_calibration_request");
assert(~logical(out.StrictSchedulingOwnership) ...
    && ~logical(out.ConnectedStrictCertified));

cfgActual = localCalibrationConfig();
actual = sixgr.link.runDLPDSCHThroughput( ...
    cfgActual, "ExecutionProfile", "phy_calibration", ...
    "NumFrames", 1, "SNR_dB", 30);
assert(actual.Ok && ~actual.Skipped, ...
    'One-frame calibration failed: %s',string(actual.Notes));
assert(height(actual.TrialTable) == 1);
spatial=actual.TrialTable;
assert(spatial.RankEstimate<=spatial.SpatialRankDimensionLimit && ...
    spatial.MinimumSnapshotRank<=spatial.RankEstimate && ...
    contains(spatial.RankEstimateSource,"numerical_svd_not_RI"), ...
    'Executed DL diagnostics must distinguish numerical rank from received RI.');
assert(all(ismember(["ResidualInterLayerPowerMean","ResidualInterLayerPowerPerLayer", ...
    "ResidualInterLayerPowerSource","ResidualInterLayerPowerStatus"], ...
    string(actual.TrialTable.Properties.VariableNames))));
assert(string(actual.TrialTable.ExecutionProfile) == "phy_calibration");
assert(string(actual.TrialTable.ExecutionBackend) ...
    == "legacy_pdsch_calibration_facades");
assert(string(actual.TrialTable.CalibrationProvenance) ...
    == "explicit_phy_calibration_request");
assert(~logical(actual.TrialTable.ConnectedStrictCertified));
localAssertFinalOutcome(actual,1);

fixture = StrictPDSCHChainFixture.create(1);
assignment = localConnectedAssignment(fixture.Assignment);
integrationContext = localIntegrationContext( ...
    assignment, fixture.PrecoderBundle, fixture.Carrier.NSizeGrid);
cfgStrict = localStrictConfig();
strict = sixgr.link.runDLPDSCHThroughput( ...
    cfgStrict, ...
    "ExecutionProfile", "connected_strict", ...
    "Assignment", assignment, ...
    "ResourcePlan", fixture.ResourcePlan, ...
    "Carrier", fixture.Carrier, ...
    "ReferenceSignalConfig", fixture.ReferenceConfig, ...
    "ReceiverConfig", fixture.ReceiverConfig, ...
    "PrecoderBundle", fixture.PrecoderBundle, ...
    "IntegrationContext", integrationContext, ...
    "TransportBlockBits", fixture.TransportBlocks, ...
    "NumFrames", 1, "SNR_dB", Inf);
assert(strict.Ok && ~strict.Skipped);
assert(strict.BER == 0 && strict.BLER == 0);
assert(strict.ConnectedStrictCertified ...
    && strict.StrictSchedulingOwnership);
assert(string(strict.ExecutionBackend) ...
    == "canonical_pdsch_compatibility_facades");
assert(string(strict.AssignmentId) == assignment.AssignmentId);
assert(string(strict.IntegrationBinding.AssignmentId) ...
    == assignment.AssignmentId);
assert(strict.TX.CanonicalDelegation && strict.RX.CanonicalDelegation);
assert(isequaln(strict.TrialTable.ResidualInterLayerPowerMean,strict.RX.ResidualInterLayerPowerMean));
assert(strict.TrialTable.ResidualInterLayerPowerStatus==strict.RX.ResidualInterLayerPowerStatus);
localAssertFinalOutcome(strict,1);

% Finite-SNR strict execution must use the configured occupied-RE energy,
% not waveform-average power (which changes with FFT occupancy and rank).
for rankValue = [1 2]
    for nfft = [128 512]
      % Build RS configuration and immutable resource plan together.
      noiseFixture = StrictPDSCHChainFixture.create(rankValue, 'NPRB', 6, ...
          'OFDMOptions', {'Nfft', nfft, 'Windowing', 0});
      noiseAssignment = localConnectedAssignment(noiseFixture.Assignment);
      noiseContext = localIntegrationContext(noiseAssignment, ...
          noiseFixture.PrecoderBundle, noiseFixture.Carrier.NSizeGrid);
      for referenceEnergy = [.25 1]
        noiseCfg = cfgStrict;
        noiseCfg.channel.awgnReferenceREEnergy = referenceEnergy;
        rngBefore = rng;
        finite = sixgr.link.runDLPDSCHThroughput(noiseCfg, ...
            'ExecutionProfile', 'connected_strict', ...
            'Assignment', noiseAssignment, ...
            'ResourcePlan', noiseFixture.ResourcePlan, ...
            'Carrier', noiseFixture.Carrier, ...
            'ReferenceSignalConfig', noiseFixture.ReferenceConfig, ...
            'ReceiverConfig', noiseFixture.ReceiverConfig, ...
            'PrecoderBundle', noiseFixture.PrecoderBundle, ...
            'IntegrationContext', noiseContext, ...
            'TransportBlockBits', noiseFixture.TransportBlocks, ...
            'NumFrames', 1, 'SNR_dB', 20);
        expectedGridNoise = referenceEnergy * 10^(-20/10);
        fprintf('STRICT_NOISE rank=%d nfft=%d Es=%g expected=%g actual=%g\n', ...
            rankValue, nfft, referenceEnergy, expectedGridNoise, ...
            finite.ChannelEvidence.GridNoiseVariance);
        assert(abs(finite.ChannelEvidence.GridNoiseVariance ...
            - expectedGridNoise) < 1e-12, ...
            'test:StrictOccupiedRENoiseMismatch', ...
            'Strict PDSCH noise must honor fixed occupied-RE Es/N0.');
        assert(isequal(rngBefore, rng), 'Strict noise reset or consumed caller RNG.');
        assert(finite.TrialTable.ConfiguredSNR_dB == 20 && ...
            finite.TrialTable.AppliedAWGNSNR_dB == 20 && ...
            finite.TrialTable.SignalEnergyPerOccupiedRE == referenceEnergy);
        % Independent complex Gaussian samples plus Toolbox demodulation
        % verify actual receiver input, not self-consistent metadata alone.
        stream = RandStream('mt19937ar','Seed',double(noiseCfg.run.seed));
        expectedNoise = sqrt(expectedGridNoise/(2*nfft)) .* ...
            complex(randn(stream,size(finite.TX.Waveform)), ...
                    randn(stream,size(finite.TX.Waveform)));
        expectedGrid = nrOFDMDemodulate(noiseFixture.Carrier, ...
            finite.TX.Waveform + expectedNoise, 'Nfft', nfft);
        assert(max(abs(finite.RX.OFDMGrid(:)-expectedGrid(:))) < 1e-11, ...
            'test:StrictReceivedNoiseSamplesMismatch', ...
            'Strict receiver samples do not match independently scaled noise.');
        localAssertFinalOutcome(finite,1);
      end
    end
end

fprintf([ ...
    'DL PDSCH throughput execution contract: 4/4 typed ownership ' ...
    'guards; actual calibration/typed TX-RX final-CW receipts retained; ' ...
    'received_PDCCH=0 unique_MAC_delivery=0.\n']);
ok = true;
end

