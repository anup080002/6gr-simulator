function assignment = localConnectedAssignment(calibration)
data = calibration.toStruct();
data.AssignmentId = string(data.AssignmentId) ...
    + "-THROUGHPUT-CONNECTED";
data.Profile = "connected_strict";
data.Source = "decoded_dci+ue_context";
data.DecodedDCIId = "DCI-THROUGHPUT-001";
data.ScheduledDCIId = "";
data.ControlAuthority = "receiver_crc_valid_decode";
data.DCIFormat = "1_1";
data.DCICRCPass = true;
data.DecodedRNTI = data.RNTI;
data.DCIRNTIMatch = true;
data.PDCCHAbsoluteSlot = data.PDSCHAbsoluteSlot;
data.K0 = 0;
data.SearchSpaceId = "SS-THROUGHPUT";
data.CORESETId = "CORESET-THROUGHPUT";
data.TCIStateId = 0;
data.TransmissionConfigurationIndication = 0;
assignment = sixgr.pdsch.PDSCHSchedulingAssignment(data);
assignment.validateForExecution();
end

function context = localIntegrationContext( ...
        assignment, precoder, activeBWPNumPRB)
data = assignment.toStruct();
digest = assignment.validateForExecution();
tci = struct( ...
    "TCIStateId", double(data.TCIStateId), ...
    "Activated", true, ...
    "SourceReferenceSignal", "NZP-CSI-RS", ...
    "SourceReferenceSignalId", "NZP-CSI-RS-THROUGHPUT", ...
    "QCLTypes", "typeD", ...
    "Assumptions", "explicit_test_qcl_state", ...
    "PrecoderContextId", "PRECODER-THROUGHPUT-001", ...
    "PrecoderBundleDigest", precoder.ImmutableBundleDigest, ...
    "PrecoderAssignmentId", assignment.AssignmentId, ...
    "PrecoderAssignmentValidationDigest", digest, ...
    "PrecoderConfigurationEpoch", double(data.ConfigurationEpoch));
context = struct( ...
    "ActiveServingCellIds", double(data.ServingCellId), ...
    "ActiveCCIds", double(data.CCId), ...
    "ActiveBWPId", double(data.BWPId), ...
    "ActiveBWPStartPRB", ...
        double(data.PRBSetCarrierRelative(1) ...
        - data.PRBSetBWPRelative(1)), ...
    "ActiveBWPNumPRB", double(activeBWPNumPRB), ...
    "ConfigurationEpoch", double(data.ConfigurationEpoch), ...
    "CarrierIndicatorValid", true, ...
    "CrossCarrierSchedulingEnabled", false, ...
    "ActivatedTCIStates", tci);
end

function localAssertIdentifier(fn, expected)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(expected), ...
        "Expected %s, observed %s (%s).", ...
        expected, ME.identifier, ME.message);
    return;
end
error("testDLPDSCHThroughputExecutionContract:MissingError", ...
    "Expected typed error %s.", expected);
end
