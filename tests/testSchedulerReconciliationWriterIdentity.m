function ok=testSchedulerReconciliationWriterIdentity()
% Both production publishers retain the same numeric schema and values.
% These are declared table fixtures, not waveform/performance evidence.
root=fullfile(pwd,'results','diagnostics','scheduler_writer_identity', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
cfg=struct('frame_timing',struct('slot_duration_ms',.5));
dl=table(repmat("DL",3,1),ones(3,1),(1:3).',repmat("tb-one",3,1), ...
    repmat(12000,3,1),[0;1;1],[0;12000;12000],[.5;1;.5],[0;12;24], ...
    [10;NaN;20],repmat("OK",3,1), ...
    'VariableNames',{'Direction','UEIndex','Slot','LogicalTBID','TBSize_bits', ...
    'CRCPass','GoodBits','AirInterfaceTTI_ms','Goodput_Mbps', ...
    'PostEqSINR_dB','PostEqSINRValueStatus'});
ul=dl; ul.Direction(:)="UL";
raw=struct('DL',dl,'UL',ul);
path=fullfile(root,'reports','csv','scheduler_kpi_reconciliation.csv');
a=sixgr.analytics.writeRFInterferenceReconciliation(cfg,root,raw,struct(),struct());
before=sixgr.phy.waveform.WaveformHash.file(path);
b=sixgr.analytics.generateMeasuredSINRCurves(root,'writer_identity', ...
    'TrialData',raw,'ScenarioConfig',cfg,'UpdateAnchorKPIs',false);
assert(isequaln(a.Tables.Scheduler,b.Tables.SchedulerKPIReconciliation) && ...
    sixgr.phy.waveform.WaveformHash.file(path)==before, ...
    'test:SchedulerWriterCollision','Measured-SINR publication replaced numeric scheduler evidence.');
assert(b.Tables.SchedulerKPIReconciliation.DL_GoodBits==12000 && ...
    b.Tables.SchedulerKPIReconciliation.DL_Goodput_Mbps==6, ...
    'Numeric scheduler population must not depend on SINR availability or row-rate means.');
assert(isfile(b.Paths.SchedulerAnchorCaseReconciliation) && ...
    ~b.Tables.SchedulerAnchorCaseReconciliation.SchedulerKpiReconciliationOk, ...
    'Absent anchor coverage must remain a separate failed audit, not erase measured metrics.');
sixgr.analytics.writeRFInterferenceReconciliation(cfg,root,raw,struct(),struct());
assert(sixgr.phy.waveform.WaveformHash.file(path)==before, ...
    'Reverse publication order changed the numeric artifact.');
ok=true;
end
