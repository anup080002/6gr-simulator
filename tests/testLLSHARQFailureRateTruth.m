function ok = testLLSHARQFailureRateTruth()
%TESTLLSHARQFAILURERATETRUTH Keep HARQ failure semantics separate from BLER aliases.

setup6GRSimToolkit("Verbose", false);

harqTimelineT = table( ...
    ["DL"; "DL"; "UL"], ...
    [1; 1; 1], ...
    [false; true; true], ...
    'VariableNames', {'Direction','UEIndex','CombinedDecodeOK'});

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

cfg = sixgr.config.defaultConfig();
dlRaw = table( ...
    [1; 1], [320; 320], [10; 10], [1; 2], [1; 1], [0; 1], [0; 0], [128; 128], [0; 0], [6; 6], [6; 6], [0; 0], ...
    ["FAIL"; "PASS"], [0; 0], ...
    'VariableNames', {'UEIndex','RNTI','SNR_dB','Frame','Slot','CRCPass','BitErrors','BitsCompared','Goodput_Mbps','ReceiverHestSINR_dB','MeasuredSINR_dB','ChannelGain_dB','Status','Crash'});
ulRaw = table( ...
    1, 320, 10, 1, 1, 1, 0, 128, 0, 8, 8, 0, "PASS", 0, ...
    'VariableNames', {'UEIndex','RNTI','SNR_dB','Frame','Slot','CRCPass','BitErrors','BitsCompared','Goodput_Mbps','ReceiverHestSINR_dB','MeasuredSINR_dB','ChannelGain_dB','Status','Crash'});

rawTrials = struct("DL", dlRaw, "UL", ulRaw, "SRS", table(), "TRS", table());
slotTrace = struct("HARQTimelineTable", harqTimelineT);

artifacts = sixgr.truth.exportLLSLiveDerivedTables(cfg, tmp, rawTrials, struct(), struct(), slotTrace);
userPerfT = artifacts.UserPerformance;
assert(height(userPerfT) == 1, "Live-derived user performance export must preserve one UE row.");
assert(abs(double(userPerfT.DL_HARQFailureRate(1)) - 0.5) < 1e-12, ...
    "DL HARQ failure rate must come from DL HARQ decode outcomes.");
assert(abs(double(userPerfT.UL_HARQFailureRate(1))) < 1e-12, ...
    "UL HARQ failure rate must come from UL HARQ decode outcomes.");
assert(double(userPerfT.DL_HARQObservationCount(1)) == 2 && double(userPerfT.UL_HARQObservationCount(1)) == 1, ...
    "Per-direction HARQ observation counts must preserve real support.");
assert(abs(double(userPerfT.HARQFailureRate(1)) - (1/3)) < 1e-12, ...
    "Live-derived HARQ failure rate must follow HARQ timeline truth, not mean(DL_BLER, UL_BLER).");
assert(double(userPerfT.HARQObservationCount(1)) == 3, ...
    "Live-derived HARQ observation count must preserve total HARQ support.");

ok = true;
end
