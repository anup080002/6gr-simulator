    "SchemaVersion", "sixgr.conformance.reference_qualification/v6", ...
    "EntryId", string(entryId), "FRC", "R.1-4-1", ...
    "Condition", "AWGN", "Required", true, "ExperimentSeed", 38104, ...
    "ExecutionAttempted", true, "Pass", true, ...
    "FullStandardExecutionExact", true, "DataChannelExact", true, ...
    "StatisticallyQualified", true, "OneSidedReferencePass", true, ...
    "Profile", "full", ...
    "EvidenceClass", "ACTUAL_FRC_FULL_STANDARD_TRUTH_EXECUTION", ...
    "Metric", "fraction_of_maximum_throughput", ...
    "Comparator", "greater_equal", "TargetFraction", 0.70, ...
    "PointEstimate", 1.0, "ConfidenceLevel", 0.95, ...
    "OneSidedLower", 0.99, "OneSidedUpper", 1.0, ...
    "PointEstimatePass", true, ...
    "ObservedConfidenceBoundSupportsPass", true, ...
    "ConfidenceQualificationEligible", true, ...
    "RequiredQualificationTransportBlocks", 9604, ...
    "ConfidenceMethod", ...
        "independent_transport_block_cluster_ratio_hoeffding_known_support", ...
    "ConfidenceSamplingPlan", ...
        "fixed_max_transport_blocks_prespecified_snr_tolerance_bracket", ...
    "StatisticalUnit", "independently_sampled_transport_block", ...
    "RequiredSNR_dB", 22.5, "MeasuredSNR_dB", NaN, "Delta_dB", NaN, ...
    "MeasuredSNRAvailable", false, ...
    "CrossingStatus", "not_evaluated_by_configuration", ...
    "CatalogSHA256", string(catalogHash), ...
    "TransportBlocks", 10000, "BlockErrors", 0, ...
    "Transmissions", 10000, "FailedTransmissionAttempts", 0, ...
    "SweepTransportBlocks", 10000, "SweepBlockErrors", 0, ...
    "SweepTransmissions", 10000, ...
    "SweepFailedTransmissionAttempts", 0, ...
    "ExecutionBackend", "existing_truth_pdsch_tx_rx", ...
    "ApproximationMode", "none", ...
    "Source", "existing_truth_phy_execution", ...
    "ProxyUsed", false, "FallbackUsed", false, ...
    "Status", "PASS", "FailureIdentifier", "", "FailureReason", "", ...
    "SourceGitCommit", string(repmat('c', 1, 40)), ...
    "SourceGitWorktreeDirty", false, "SourceMATLABRelease", "2026a", ...
    "SourceStateSHA256", string(repmat('d', 1, 64)), ...
    "SymmetricRegressionRequired", false, ...
    "SymmetricRegressionPass", false, ...
    "SymmetricRegressionStatisticallyQualified", false);
end

function localAssertRejected(T, message)
[passed, failure] = ...
    sixgr.conformance.validateReferenceQualificationTable(T);
assert(~passed && failure == ...
    "frc_reference_qualification_required_row_failed", message);
end
