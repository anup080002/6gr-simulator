function ok = testFRCReferenceQualificationReducerSemantics()
%TESTFRCREFERENCEQUALIFICATIONREDUCERSEMANTICS One-sided and symmetric gates differ.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
hash = string(repmat('a', 1, 64));
T = table(true, true, true, true, true, "full", ...
    "ACTUAL_FRC_FULL_STANDARD_TRUTH_EXECUTION", 22.5, NaN, NaN, ...
    false, "not_evaluated_by_configuration", hash, 10000, 0, 10000, 0, ...
    false, false, false, ...
    'VariableNames', {'Pass','FullStandardExecutionExact', ...
    'DataChannelExact','StatisticallyQualified','OneSidedReferencePass', ...
    'Profile','EvidenceClass','RequiredSNR_dB','MeasuredSNR_dB', ...
    'Delta_dB','MeasuredSNRAvailable','CrossingStatus', ...
    'CatalogSHA256','TransportBlocks','BlockErrors','Transmissions', ...
    'FailedTransmissionAttempts', ...
    'SymmetricRegressionRequired','SymmetricRegressionPass', ...
    'SymmetricRegressionStatisticallyQualified'});

[passed, failure, details] = ...
    sixgr.conformance.validateReferenceQualificationTable(T);
assert(passed && strlength(failure) == 0 && details.Evaluated && ...
    details.RequiredRowCount == 1 && ...
    details.SymmetricRequiredRowCount == 0 && ...
    details.CrossingDisclosurePass, ...
    ("A one-sided 3GPP reference-point pass must not require a finite " + ...
    "nonnormative symmetric crossing."));

T.SymmetricRegressionRequired = true;
[passed, failure] = ...
    sixgr.conformance.validateReferenceQualificationTable(T);
assert(~passed && failure == ...
    "frc_reference_qualification_required_row_failed", ...
    "A required symmetric regression must fail when its crossing is absent.");

T.MeasuredSNR_dB = 22.2;
T.Delta_dB = -0.3;
T.MeasuredSNRAvailable = true;
T.CrossingStatus = "confidence_qualified_prespecified_tolerance_bracket";
T.SymmetricRegressionPass = true;
T.SymmetricRegressionStatisticallyQualified = true;
[passed, failure] = ...
    sixgr.conformance.validateReferenceQualificationTable(T);
assert(passed && strlength(failure) == 0, ...
    "A required, finite, statistically qualified symmetric regression should pass.");

T.OneSidedReferencePass = false;
[passed, failure] = ...
    sixgr.conformance.validateReferenceQualificationTable(T);
assert(~passed && failure == ...
    "frc_reference_qualification_required_row_failed", ...
    "Optional symmetric evidence must never rescue a failed one-sided gate.");
ok = true;
end
