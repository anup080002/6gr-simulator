function ok = testFRCReferenceQualificationReducerSemantics()
%TESTFRCREFERENCEQUALIFICATIONREDUCERSEMANTICS Recompute every FRC gate.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
hash = string(repmat('a', 1, 64));
entryId = "dl_r_pdsch_1_4_1_fdd_atg_awgn";
T = struct2table(localValidRow(entryId, hash));

[passed, failure, details] = ...
    sixgr.conformance.validateReferenceQualificationTable(T);
assert(passed && strlength(failure) == 0 && details.Evaluated && ...
    details.RequiredRowCount == 1 && details.SchemaContractPass && ...
    details.EntryIdentityPass && details.EntrySetPass && ...
    details.CatalogMembershipPass && details.CatalogBindingPass && ...
    details.TruthLineagePass && details.SourceReproducibilityPass && ...
    details.MetricConsistencyPass && details.StatisticalContractPass && ...
    details.DecisionConsistencyPass && ...
    details.SymmetricRequiredRowCount == 0 && ...
    details.CrossingDisclosurePass, ...
    ("A complete one-sided 3GPP reference-point row must pass without " + ...
    "requiring a nonnormative symmetric crossing."));

T.SymmetricRegressionRequired = true;
T.Pass = false;
T.Status = "FAIL";
T.FailureReason = "required_symmetric_reference_regression_failed";
[passed, failure] = ...
    sixgr.conformance.validateReferenceQualificationTable(T);
assert(~passed && failure == ...
    "frc_reference_qualification_required_row_failed", ...
    "A required symmetric regression must fail when its crossing is absent.");

T.MeasuredSNR_dB = 22.2;
T.Delta_dB = -0.3;
T.MeasuredSNRAvailable = true;
T.CrossingStatus = "confidence_qualified_prespecified_tolerance_bracket";
T.SymmetricRegressionPass = true;
T.SymmetricRegressionStatisticallyQualified = true;
T.Pass = true;
T.Status = "PASS";
T.FailureReason = "";
[passed, failure] = ...
    sixgr.conformance.validateReferenceQualificationTable(T);
assert(passed && strlength(failure) == 0, ...
    "A required, finite, statistically qualified symmetric regression should pass.");

baseline = struct2table(localValidRow(entryId, hash));

bad = baseline;
bad.OneSidedReferencePass = false;
localAssertRejected(bad, ...
    "A self-reported Pass cannot rescue a failed one-sided gate.");

[passed, failure] = ...
    sixgr.conformance.validateReferenceQualificationTable(baseline, ...
    "ExpectedEntryIds", [entryId; "ul_g_fr1_a3a_1_awgn"]);
assert(~passed && failure == ...
    "frc_reference_qualification_entry_set_mismatch", ...
    ["A passing subset must not satisfy a qualification whose YAML " ...
    "requested additional FRC entries."]);

[passed, failure] = ...
    sixgr.conformance.validateReferenceQualificationTable(baseline, ...
    "ExpectedEntryIds", entryId, ...
    "ExpectedCatalogSHA256", string(repmat('b', 1, 64)));
assert(~passed && failure == ...
    "frc_reference_qualification_required_row_failed", ...
    "A stale table from a different FRC catalog hash must fail closed.");

[passed, failure, details] = ...
    sixgr.conformance.validateReferenceQualificationTable(baseline, ...
    "ExpectedEntryIds", entryId, ...
    "CatalogEntryIds", "a_different_catalog_entry", ...
    "ExpectedCatalogSHA256", hash);
assert(~passed && failure == ...
    "frc_reference_qualification_catalog_entry_missing" && ...
    ~details.CatalogMembershipPass, ...
    "A table entry absent from the active catalog must fail closed.");

bad = baseline;
bad.TransportBlocks = 9603;
bad.SweepTransportBlocks = 9603;
bad.PointEstimate = 1;
localAssertRejected(bad, ...
    "A reported statistical pass below its prespecified TB floor must fail.");

bad = baseline;
bad.ProxyUsed = true;
localAssertRejected(bad, ...
    "Proxy evidence must never pass the primary FRC qualification reducer.");

bad = baseline;
bad.FallbackUsed = true;
localAssertRejected(bad, ...
    "Fallback evidence must never pass the primary FRC qualification reducer.");

bad = baseline;
bad.ApproximationMode = "fast_proxy";
localAssertRejected(bad, ...
    "An approximate execution cannot be relabeled as FRC truth.");

bad = baseline;
bad.PointEstimate = 0.69;
localAssertRejected(bad, ...
    "The reducer must recompute the metric from normative-point counts.");

bad = baseline;
bad.OneSidedLower = 0.5;
localAssertRejected(bad, ...
    "The reducer must recompute confidence-bound support.");

bad = baseline;
bad.SourceGitWorktreeDirty = true;
localAssertRejected(bad, ...
    "A dirty-source execution cannot satisfy publication qualification.");

bad = baseline;
bad.SourceStateSHA256 = "not-a-source-hash";
localAssertRejected(bad, ...
    "A missing production-source byte identity must fail closed.");

bad = baseline;
bad.SchemaVersion = "sixgr.conformance.reference_qualification/v5";
[passed, failure] = ...
    sixgr.conformance.validateReferenceQualificationTable(bad);
assert(~passed && failure == ...
    "frc_reference_qualification_schema_invalid", ...
    "A stale qualification schema must not be accepted.");
ok = true;
end

