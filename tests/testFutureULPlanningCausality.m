function ok = testFutureULPlanningCausality()
% Future resource selection must not execute future receivers or arrivals.
% Constructed pending records below test scheduler ownership, not air truth.
setup6GRSimToolkit('Verbose',false);
source = sixgr.lls6g.config.loadScenarioConfig(fullfile('simulator','configs', ...
    'scenarios','lls_causal_access_to_data_wiring_tdd.yaml'));
cfg = sixgr.lls6g.buildInternalConfig(source,tempname);
multi = struct('Enabled',true,'NumUsers',1,'RNTIStart',1, ...
    'ExecutionModel','slot_coupled_truth');
state = sixgr.truth.CoupledTruthRuntime.initialize(cfg,tempname,multi,struct(),10);
state = sixgr.truth.CoupledTruthRuntime.advanceFrame(state,cfg,multi,1,12);
state = sixgr.truth.CoupledTruthRuntime.startSlot(state,cfg,'DL',1,1,1,10,12);
state.ULQueueBits(:) = 0;
state.Traffic.OfferedBitsUL(5,:) = 1e6;
state.PUCCHGrantTraceTable = table(false,5, ...
    'VariableNames',{'GrantExecutedFlag','ScheduledAbsoluteSlot'});
state.PendingCSITable = table(false,5,"DL",1, ...
    'VariableNames',{'Processed','DueSlot','Direction','UEIndex'});
state.PUCCHExecutedCurrentSlotGrantSnapshot = table("current-slot-only", ...
    'VariableNames',{'FixtureIdentity'});
beforeRNG = rng;
beforeHARQ = state.DLHarq.Stats;
profile clear; profile on;
cleanup = onCleanup(@()profile('off')); %#ok<NASGU>
plan = sixgr.truth.CoupledTruthRuntime.futureULPlanningView(state,5);
profile off; stats = profile('info');
names = string({stats.FunctionTable.FunctionName});
for forbidden = ["processDueFeedback","enqueueTrafficForFrame", ...
        "recordSlotTraceStart","applyRuntimeFadingChannel", ...
        "observePUCCHFeedback","observeCSIReport","advanceFrameImpl"]
    assert(~any(contains(names,forbidden)), ...
        'Future UL resource planning executed %s.',forbidden);
end
assert(isequaln(beforeRNG,rng) && isequaln(beforeHARQ,state.DLHarq.Stats));
assert(plan.CurrentSlot==5 && plan.CurrentCanonicalSlot==1 && ...
    plan.PlanningDecisionSlot==1 && plan.PlanningTrafficThroughSlot==1 && ...
    plan.TimingControlAbsoluteSlot0Based==0);
assert(plan.CurrentDirection=="UL" && plan.CurrentSlotULAllowed && ...
    plan.CurrentSlotULNumSymbols==state.SymbolsPerSlot && ~plan.CurrentSlotDLAllowed);
assert(all(plan.ULQueueBits==0) && plan.LastTrafficFrameApplied==1 && ...
    isequaln(plan.PendingCSITable,state.PendingCSITable) && ...
    isequaln(plan.PUCCHGrantTraceTable,state.PUCCHGrantTraceTable) && ...
    isequaln(plan.SlotTraceTable,state.SlotTraceTable) && ...
    isequaln(plan.PUCCHExecutedCurrentSlotGrantSnapshot, ...
        state.PUCCHExecutedCurrentSlotGrantSnapshot));
% Actual queue-backed UE construction consumes the planning view without
% inventing a demand from the pre-generated future traffic matrix.
[planned,ue] = sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime( ...
    plan,cfg,1,'UL',1);
assert(ue.ULBufferBytes==0 && ~ue.Active && all(planned.ULQueueBits==0));
assert(isequaln(planned.PendingCSITable,state.PendingCSITable));
queued = state; queued.ULQueueBits(:)=80;
queuedPlan = sixgr.truth.CoupledTruthRuntime.futureULPlanningView(queued,5);
[~,ue] = sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime(queuedPlan,cfg,1,'UL',1);
assert(ue.ULBufferBytes==10,'Only the 80 already-arrived bits belong in this queue view.');

% Optional SRS still obeys required access. A future resource calendar may
% not promote a provisional RAR into a completed RRC/access procedure.
srsCfg=cfg;
srsPlan=plan;
% Keep the installed periodic resource intact: canonical slot 5 is its
% configured period-5/offset-4 occasion. This test changes access knowledge,
% not the resource calendar independently of the native SRS configuration.
assert(srsPlan.SRSSlotPeriod==srsCfg.phy.srs.period_slots && ...
    sixgr.truth.coupledSRSResourceOpportunity(srsCfg,5,1,srsPlan.NumUsers, ...
        srsPlan.SRSSlotPeriod,srsCfg.phy.srs.schedulingPolicy,srsCfg.phy.srs.maxUEsPerSlot));
srsPlan.LastSRSSlotByUE(:)=NaN;
srsPlan.ControlGating.SRSRequired=false;
srsPlan.ControlGating.PRACHRequired=true;
srsPlan.AccessState(:)="not_attempted";
srsPlan.LastSuccessfulPRACHSlotByUE(:)=NaN;
assert(~sixgr.truth.coupledSRSAttemptDue(srsPlan,srsCfg,5,1), ...
    'Optional SRS must not run over an unfinished required access procedure.');
srsPlan.AccessState(:)="succeeded";
srsPlan.LastSuccessfulPRACHSlotByUE(:)=4;
assert(~sixgr.truth.coupledSRSAttemptDue(srsPlan,srsCfg,5,1), ...
    'Future access completion is not known at the grant decision.');
srsPlan.LastSuccessfulPRACHSlotByUE(:)=1;
assert(sixgr.truth.coupledSRSAttemptDue(srsPlan,srsCfg,5,1), ...
    'SRS must resume on its configured occasion after causal access completion.');
srsPlan.ControlGating.PRACHRequired=false;
srsPlan.AccessState(:)="not_required";
srsPlan.LastSuccessfulPRACHSlotByUE(:)=NaN;
assert(sixgr.truth.coupledSRSAttemptDue(srsPlan,srsCfg,5,1), ...
    'An explicitly access-free component scenario must retain its SRS occasions.');

% Freshness at the future data slot is distinct from availability at the
% current grant decision. Newer not-yet-delivered measurements cannot win.
plan.ReferenceSignalMeasurementTable = table(["SRS";"SRS"],["UE";"UE"], ...
    [1;1],[1;1],[1;4],[true;true],["known_at_control";"future_delivery"], ...
    'VariableNames',{'SignalType','TargetType','TargetId','ProducerSlot', ...
        'AvailableSlot','Valid','MeasurementId'});
measurement = sixgr.truth.CoupledTruthRuntime.consumeReferenceSignalMeasurementRuntime( ...
    plan,'SRS','UE',1,5,10);
assert(measurement.Usable && measurement.MeasurementId=="known_at_control" && ...
    measurement.AgeSlots==4 && measurement.KnownAtSlot==1);
stale = sixgr.truth.CoupledTruthRuntime.consumeReferenceSignalMeasurementRuntime( ...
    plan,'SRS','UE',1,5,2);
assert(~stale.Usable && stale.Status=="stale");
plan.ReferenceSignalMeasurementTable = plan.ReferenceSignalMeasurementTable(2,:);
future = sixgr.truth.CoupledTruthRuntime.consumeReferenceSignalMeasurementRuntime( ...
    plan,'SRS','UE',1,5,10);
assert(~future.Usable && future.Status=="future_measurement_not_available" && ...
    future.Blocker=="reference_signal_measurement_available_after_knowledge_slot");
ordinary = sixgr.phy.refsig.causalMeasurementState( ...
    plan.ReferenceSignalMeasurementTable,5,'MaxAgeSlots',10);
assert(ordinary.Usable && ordinary.KnownAtSlot==5);
localReject(@()sixgr.phy.refsig.causalMeasurementState( ...
    plan.ReferenceSignalMeasurementTable,5,'KnownAtSlot',6), ...
    'sixgr:phy:refsig:CausalMeasurementBadKnowledgeSlot');
localReject(@()sixgr.phy.refsig.causalMeasurementState( ...
    plan.ReferenceSignalMeasurementTable,5,'KnownAtSlot',1+1i), ...
    'sixgr:phy:refsig:CausalMeasurementBadKnowledgeSlot');
badMeasurement = plan.ReferenceSignalMeasurementTable;
badMeasurement.ProducerSlot(:)=4; badMeasurement.AvailableSlot(:)=1;
localReject(@()sixgr.phy.refsig.causalMeasurementState( ...
    badMeasurement,5,'KnownAtSlot',1), ...
    'sixgr:phy:refsig:CausalMeasurementInvalidTiming');
plan.LastSuccessfulSRSSlotByUE(:)=4;
plan.LastSuccessfulTRSSlotByCell(:)=4;
[refreshed,~] = sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime(plan,cfg,1,'UL',1);
assert(all(refreshed.SRSValidityState~="valid") && ...
    all(refreshed.TRSValidityStateByCell~="valid"));
% The same negative-age defect must be rejected at a real current slot.
actual = state;
actual.LastSuccessfulSRSSlotByUE(:)=4;
actual.LastSuccessfulTRSSlotByCell(:)=4;
[refreshed,~] = sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime(actual,cfg,1,'UL',1);
assert(all(refreshed.SRSValidityState~="valid") && ...
    all(refreshed.TRSValidityStateByCell~="valid"));

localReject(@()sixgr.truth.CoupledTruthRuntime.startSlot( ...
    plan,cfg,'UL',1,1,5,10,12),'sixgr:truth:ExecutionFromPlanningView');
localReject(@()sixgr.truth.CoupledTruthRuntime.advanceFrame( ...
    plan,cfg,multi,5,12),'sixgr:truth:ExecutionFromPlanningView');
localReject(@()sixgr.truth.CoupledTruthRuntime.enqueueTrafficForFrameRuntime( ...
    plan,5),'sixgr:truth:ExecutionFromPlanningView');
localReject(@()sixgr.truth.CoupledTruthRuntime.acquireRuntimeChannelStateForControl( ...
    plan,cfg,1,'UL'),'sixgr:truth:ExecutionFromPlanningView');
localReject(@()sixgr.truth.CoupledTruthRuntime.commitRuntimeChannelState( ...
    plan,struct()),'sixgr:truth:ExecutionFromPlanningView');
localReject(@()sixgr.truth.CoupledTruthRuntime.buildTrialContextFromGrant( ...
    plan,cfg,1,'UL',struct()),'sixgr:truth:ExecutionFromPlanningView');
localReject(@()sixgr.truth.CoupledTruthRuntime.completeSlot( ...
    plan,cfg,1,'UL',table(),struct()),'sixgr:truth:ExecutionFromPlanningView');
localReject(@()sixgr.truth.CoupledTruthRuntime.observePUCCHFeedbackRuntime( ...
    plan,table()),'sixgr:truth:ExecutionFromPlanningView');
localReject(@()sixgr.truth.CoupledTruthRuntime.futureULPlanningView( ...
    plan,10),'sixgr:truth:ExecutionFromPlanningView');

% Slot-46 PDCCH schedules slot-50 PUSCH. TRS delivered at 29 is fresh
% for the CONTROL reception (age 17), not age 21 at the future UL resource.
% The SRS must nevertheless remain fresh for PUSCH (45 -> 50, age 5).
boundary=state;
boundary.CurrentSlot=46; boundary.CurrentCanonicalSlot=46;
boundary.LastTrafficFrameApplied=46; boundary.ULQueueBits(:)=8000;
boundary.ControlGating.PBCHRequired=false;
boundary.ControlGating.PRACHRequired=false;
boundary.ControlGating.TRSRequired=true;
boundary.ControlGating.TRSMaxAgeSlots=20;
boundary.ControlGating.SRSRequired=true;
boundary.ControlGating.SRSMaxAgeSlots=5;
boundary.LastSuccessfulTRSSlotByCell(:)=29;
boundary.LastSuccessfulSRSSlotByUE(:)=45;
% Declared delivery-boundary fixture, not a received waveform. Raw sounding
% freshness alone is not an accepted rank/TPMI decision. Give the positive
% clock case one explicitly identified tuple, without bypassing either gate.
declaredSRS=struct('MeasurementId',"declared_future_ul_clock_srs", ...
    'SignalType',"SRS",'TargetType',"UE",'TargetId',1, ...
    'ServingCell',double(boundary.CurrentServingIdx(1)), ...
    'ProducerSlot',45,'AvailableSlot',46,'Valid',true,'RI',1,'PMI',0, ...
    'MeasurementSource',"declared_future_ul_clock_component_fixture", ...
    'MeasurementClockDomain',"slot_only");
boundary.ReferenceSignalMeasurementTable=struct2table(declaredSRS,'AsArray',true);
missingAccepted=sixgr.truth.CoupledTruthRuntime.futureULPlanningView(boundary,50);
[missingRefreshed,missingUE]=sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime( ...
    missingAccepted,cfg,1,'UL',1);
assert(~missingUE.Active && missingUE.SRSCausalUsable && ...
    ~missingUE.AcceptedSRSCausalUsable && ...
    string(missingUE.AcceptedSRSCausalStatus)=="accepted_srs_spatial_identity_unavailable" && ...
    all(missingRefreshed.TRSValidityStateByCell=="valid"), ...
    'Fresh raw sounding and tracking cannot replace a missing accepted SRS tuple.');
feedback=sixgr.truth.CoupledTruthRuntime.emptyLatestFeedbackRowRuntime();
feedback.Valid=true; feedback.Direction='UL'; feedback.Slot=45;
feedback.ServingCell=declaredSRS.ServingCell;
feedback.RI=declaredSRS.RI; feedback.PMI=declaredSRS.PMI;
feedback.CQI=10; feedback.SINR_dB=20;
feedback.SourceSlot=45; feedback.DueSlot=46; feedback.DeliveredSlot=46;
feedback.SpatialDecisionSourceSlot=45; feedback.SpatialDecisionDeliveredSlot=46;
rnti=sixgr.truth.CoupledRadioIdentity.resolve(boundary,1,declaredSRS.ServingCell);
feedback.AcceptedSRSSpatialDecision=sixgr.truth.captureAcceptedSRSSpatialDecision( ...
    declaredSRS,rnti,declaredSRS.RI,declaredSRS.PMI);
boundary.LatestULFeedback(1)=feedback;
futurePlan=sixgr.truth.CoupledTruthRuntime.futureULPlanningView(boundary,50);
[refreshed,ue]=sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime(futurePlan,cfg,1,'UL',1);
assert(ue.Active && ue.SRSCausalUsable && ue.AcceptedSRSCausalUsable && ...
    ue.AcceptedSRSCausalAgeSlots==5 && ue.FeedbackKnownAtSlot==46 && ...
    isequaln(ue.AcceptedSRSSpatialDecision,feedback.AcceptedSRSSpatialDecision) && ...
    all(refreshed.TRSValidityStateByCell=="valid"), ...
    'Fresh decision-time DL tracking must not block an SRS-qualified future UL grant.');
assert(sixgr.truth.CoupledTruthRuntime.trsAgeSlotsRuntime(refreshed,1,1)==17, ...
    'Reported TRS age must use the same decision clock as UL control admission.');
futurePlan.ControlGating.SRSMaxAgeSlots=4;
[~,ue]=sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime(futurePlan,cfg,1,'UL',1);
assert(~ue.Active && ~ue.AcceptedSRSCausalUsable, ...
    'Do not relax the PUSCH-time SRS freshness requirement.');
futurePlan.ControlGating.SRSMaxAgeSlots=5;
futurePlan.LastSuccessfulTRSSlotByCell(:)=25;
[~,ue]=sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime(futurePlan,cfg,1,'UL',1);
assert(~ue.Active && ue.AcceptedSRSCausalUsable, ...
    'Stale tracking at the PDCCH decision must still block the UL grant.');

% Exact requested n40 tail, with its real installed K2/age policy. The
% feedback values below remain explicitly declared delivery-boundary data:
% this does not claim that slot-60 SRS or slot-65 PUSCH was received.
n40Source=sixgr.lls6g.config.loadScenarioConfig(fullfile('simulator','configs', ...
    'scenarios','lls_tdd_n40_20mhz_64txru_4rx_cdlc100_reference_snr_sweep.yaml'));
n40Cfg=sixgr.lls6g.buildInternalConfig(n40Source,tempname);
assert(n40Source.get('control_gating.srs_max_age_slots')==5 && ...
    n40Source.get('control_gating.trs_max_age_slots')==20);
tailGrant=struct('Direction','UL','Slot',60,'ControlAbsoluteSlot',60, ...
    'SymbolAllocation',n40Cfg.phy.pusch.symbolAllocation, ...
    'ControlSymbolAllocation',n40Cfg.phy.pdcch.symbolAllocation, ...
    'TimingAdvanceTicks',0);
tailTiming=sixgr.phy.frame.TimingRelationEngine.resolveProductionGrant(n40Cfg,tailGrant);
assert(tailTiming.Valid && tailTiming.ControlAbsoluteSlot==60 && ...
    tailTiming.DataAbsoluteSlot==64, ...
    'Original n40 timing must map canonical control 61 to UL resource 65.');
tail=boundary;
tail.CurrentSlot=61; tail.CurrentCanonicalSlot=61; tail.LastTrafficFrameApplied=61;
tail.LastSuccessfulTRSSlotByCell(:)=48;
tail.LastSuccessfulSRSSlotByUE(:)=60;
tail.ControlGating.SRSMaxAgeSlots=n40Source.get('control_gating.srs_max_age_slots');
tail.ControlGating.TRSMaxAgeSlots=n40Source.get('control_gating.trs_max_age_slots');
tailMeasurement=declaredSRS;
tailMeasurement.MeasurementId="declared_n40_tail_source60";
tailMeasurement.ProducerSlot=60; tailMeasurement.AvailableSlot=61;
tail.ReferenceSignalMeasurementTable=struct2table(tailMeasurement,'AsArray',true);
tailFeedback=feedback;
tailFeedback.Slot=60; tailFeedback.SourceSlot=60;
tailFeedback.DueSlot=61; tailFeedback.DeliveredSlot=61;
tailFeedback.SpatialDecisionSourceSlot=60;
tailFeedback.SpatialDecisionDeliveredSlot=61;
tailFeedback.AcceptedSRSSpatialDecision=sixgr.truth.captureAcceptedSRSSpatialDecision( ...
    tailMeasurement,rnti,tailMeasurement.RI,tailMeasurement.PMI);
tail.LatestULFeedback(1)=tailFeedback;
tailPlan=sixgr.truth.CoupledTruthRuntime.futureULPlanningView(tail,65);
[~,tailUE]=sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime(tailPlan,cfg,1,'UL',1);
assert(tailUE.Active && tailUE.AcceptedSRSCausalUsable && ...
    tailUE.AcceptedSRSCausalAgeSlots==5 && tailUE.FeedbackKnownAtSlot==61 && ...
    tailUE.SpatialDecisionSourceSlot==60 && tailUE.SpatialDecisionDeliveredSlot==61);
futureTail=tailMeasurement;
futureTail.MeasurementId="declared_future_source65";
futureTail.ProducerSlot=65; futureTail.AvailableSlot=66;
tailPlan.ReferenceSignalMeasurementTable=[tailPlan.ReferenceSignalMeasurementTable; ...
    struct2table(futureTail,'AsArray',true)];
selected=sixgr.truth.CoupledTruthRuntime.consumeReferenceSignalMeasurementRuntime( ...
    tailPlan,'SRS','UE',1,65,tail.ControlGating.SRSMaxAgeSlots);
assert(selected.Usable && selected.MeasurementId==tailMeasurement.MeasurementId && ...
    selected.AgeSlots==5 && selected.KnownAtSlot==61, ...
    'A future slot-65 pilot cannot displace the source known when control 61 was authored.');
futureDecision=sixgr.truth.captureAcceptedSRSSpatialDecision( ...
    futureTail,rnti,futureTail.RI,futureTail.PMI);
unavailable=sixgr.truth.consumeAcceptedSRSSpatialDecision( ...
    tailPlan,futureDecision,1,rnti,futureTail.RI,futureTail.PMI,cfg);
assert(~unavailable.Usable && unavailable.Status=="future_measurement_not_available");
tailPlan.ControlGating.SRSMaxAgeSlots=4;
[~,expiredTail]=sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime(tailPlan,cfg,1,'UL',1);
assert(~expiredTail.Active && ~expiredTail.AcceptedSRSCausalUsable, ...
    'The exact tail must fail at age four; the test must not widen age to schedule it.');
fprintf('N40_TAIL_UL_CLOCK_PASS source=60 decision=61 target=65 age=5 future65_rejected=1 waveform_execution=0\n');
localReject(@()sixgr.truth.CoupledTruthRuntime.futureULPlanningView( ...
    state,2),'sixgr:truth:InvalidULPlanningOccasion');
bad = state; bad.LastTrafficFrameApplied=5;
localReject(@()sixgr.truth.CoupledTruthRuntime.futureULPlanningView( ...
    bad,5),'sixgr:truth:InvalidULPlanningClock');
bad = state; bad.CurrentCanonicalSlot=2;
localReject(@()sixgr.truth.CoupledTruthRuntime.futureULPlanningView( ...
    bad,5),'sixgr:truth:InvalidULPlanningClock');
bad = state; bad.LatestULFeedback(1).Valid=true;
bad.LatestULFeedback(1).SourceSlot=1; bad.LatestULFeedback(1).DeliveredSlot=4;
localReject(@()sixgr.truth.CoupledTruthRuntime.futureULPlanningView( ...
    bad,5),'sixgr:truth:NoncausalULPlanningFeedback');
bad.LatestULFeedback(1).DeliveredSlot=NaN;
localReject(@()sixgr.truth.CoupledTruthRuntime.futureULPlanningView( ...
    bad,5),'sixgr:truth:NoncausalULPlanningFeedback');

% The main planner must use this production boundary, not start a future
% physical slot and then throw away the value copy with mutated handles.
code = fileread(which('sixgr.truth.runWaveformLinkBundle'));
first = regexp(code,'(?m)^function[^\r\n]*= localScheduleCoupledFutureULGrantsFromDLControl\(','start');
last = strfind(code,'function [state,pendingULGrants]=localTransmitCoupledFutureULGrants(');
assert(isscalar(first) && isscalar(last) && last>first, ...
    'The production future-UL planner must have one identifiable function boundary.');
delegate = string(code(first(1):last(1)-1));
planner = string(fileread(which('sixgr.truth.planFutureULGrants')));
assert(contains(delegate,'sixgr.truth.planFutureULGrants(') && ...
    ~contains(delegate,'CoupledTruthRuntime.startSlot') && ...
    ~contains(delegate,'enqueueTrafficForFrameRuntime') && ...
    contains(planner,'CoupledTruthRuntime.futureULPlanningView') && ...
    ~contains(planner,'CoupledTruthRuntime.startSlot') && ...
    ~contains(planner,'enqueueTrafficForFrameRuntime'));
fprintf('FUTURE_UL_PLANNING_CAUSALITY_PASS\n');
ok = true;
end

function localReject(fn,id)
try, fn(); catch ME
    assert(string(ME.identifier)==id,'Expected %s, got %s: %s',id,ME.identifier,ME.message);
    return;
end
error('testFutureULPlanningCausality:MissingError','Expected %s.',id);
end
