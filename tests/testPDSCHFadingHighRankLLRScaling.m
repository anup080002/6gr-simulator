function tests = testPDSCHFadingHighRankLLRScaling
%TESTPDSCHFADINGHIGHRANKLLRSCALING Guard resource-selective LLR scaling.
tests = functiontests(localfunctions);
end

function testHighRankTwoCodewordCDLUsesPerSymbolNoise(testCase)
probe = sixgr.pdsch.PDSCHCoverageExecutor.runReceiverTruthPoint( ...
    "CDL-C", ...
    "Rank",6, ...
    "Modulation","256QAM", ...
    "SNRdB",65, ...
    "Seed",89, ...
    "NumTrials",1, ...
    "NumerologyKHz",30, ...
    "MappingType","B", ...
    "DMRSConfigurationType",2, ...
    "DMRSLength",2, ...
    "DMRSAdditionalPosition",0, ...
    "DMRSMultiplexing","basic", ...
    "DMRSPortSet",0:5, ...
    "PTRSEnabled",true, ...
    "ReservationMode","none", ...
    "PrecodingMode","prg_noncodebook", ...
    "RV",0, ...
    "PRBSet",0:5, ...
    "ExecutionLabel","high_rank_llr_scaling_regression");

trial = probe.TrialTable;
verifyTrue(testCase,probe.Passed);
verifyTrue(testCase,trial.CRCPass);
verifyEqual(testCase,trial.BitErrors,0);
verifyEqual(testCase,trial.NumReceiveAntennas,24);
verifyEqual(testCase,trial.ChannelEstimateSource, ...
    "nrChannelEstimate_prg_stitched");
verifyEqual(testCase,trial.PostEqSINRSource, ...
    "transmitted_symbol_referenced_equalized_evm");
verifyGreaterThan(testCase,trial.PostEqSINR_dB,20);
verifyGreaterThan(testCase,trial.BitsCompared,40);
end
