function ok = testLLSTrafficFlowOwnership()
%TESTLLSTRAFFICFLOWOWNERSHIP Guard explicit-vs-derived traffic flow ownership.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

legacyPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml");
legacyScfg = sixgr.lls6g.config.loadScenarioConfig(legacyPath);
legacyCfg = sixgr.lls6g.buildInternalConfig(legacyScfg, fullfile(tmp, "legacy"));

assert(isfield(legacyCfg.traffic, "flows") && ~isempty(legacyCfg.traffic.flows), ...
    "Legacy scalar traffic config must resolve a runtime traffic flow object.");
assert(strcmp(string(legacyCfg.traffic.flowSource), "traffic.scalar_profile_fields"), ...
    "Legacy scalar traffic config must disclose scalar-derived flow ownership.");
assert(strcmp(string(legacyCfg.traffic.flowDerivationMode), "derived_from_scalar_traffic_config"), ...
    "Legacy scalar traffic config must disclose derived flow mode.");
assert(logical(legacyCfg.traffic.flowResolvedFlag), ...
    "Legacy scalar traffic config must set TrafficFlowResolvedFlag.");

traffic = sixgr.system.TrafficFactory.generate(legacyCfg, 2, 1, 1e-3);
assert(istable(traffic.FlowTable) && height(traffic.FlowTable) >= 1, ...
    "Strict runtime traffic generation must consume the resolved derived flow table.");

explicitPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "lls_6g_4ghz_100mhz_19site_3sector_100ue_uma.yaml");
explicitScfg = sixgr.lls6g.config.loadScenarioConfig(explicitPath);
  explicitCfg = sixgr.lls6g.buildInternalConfig(explicitScfg, fullfile(tmp, "explicit"));
  assert(strcmp(string(explicitCfg.traffic.flowSource), "traffic.flows"), ...
      "Explicit traffic.flows must remain explicitly owned.");
  assert(strcmp(string(explicitCfg.traffic.flowDerivationMode), "explicit_yaml_or_browser"), ...
      "Explicit traffic.flows must not be relabeled as scalar-derived.");
  assert(numel(explicitCfg.traffic.flows) >= 1, ...
      "Explicit scenario must preserve its configured flow objects.");
  explicitTraffic = sixgr.system.TrafficFactory.generate(explicitCfg, 100, 4, 5e-4);
  assert(istable(explicitTraffic.FlowTable) && all(ismember(["TransportSemanticClass","TransportTruthLabel","TransportApproximationReason"], ...
      string(explicitTraffic.FlowTable.Properties.VariableNames))), ...
      "Runtime flow table must expose transport provenance and approximation semantics.");
  ftpMask = string(explicitTraffic.FlowTable.Name) == "ftp3_bursty_broadband";
  assert(nnz(ftpMask) == 1, ...
      "Explicit 4 GHz scenario must preserve the FTP3-like flow row.");
  assert(strcmp(string(explicitTraffic.FlowTable.Protocol(ftpMask)), "UDP") && ...
      strcmp(string(explicitTraffic.FlowTable.ServiceProfile(ftpMask)), "FTP3_LIKE"), ...
      "FTP3-like scenario flow must remain explicitly configured as UDP plus FTP3_LIKE service profile.");
  assert(strcmp(string(explicitTraffic.FlowTable.TransportSemanticClass(ftpMask)), "ftp3_like_udp_offered_load_approximation") && ...
      strcmp(string(explicitTraffic.FlowTable.TransportTruthLabel(ftpMask)), "approximate_not_truthful_tcp") && ...
      contains(string(explicitTraffic.FlowTable.TransportApproximationReason(ftpMask)), "udp_offered_load") && ...
      contains(string(explicitTraffic.FlowTable.TransportApproximationReason(ftpMask)), "ftp_session"), ...
      "FTP3-like runtime flow provenance must stay explicit that the active transport is a UDP offered-load approximation, not truthful TCP.");
  assert(strcmp(string(explicitTraffic.TransportTruthLabel), "contains_approximate_transport_semantics") && ...
      contains(string(explicitTraffic.TransportApproximationReason), "ftp3_like_profile_uses_udp_offered_load"), ...
      "Traffic summary provenance must surface the FTP3-like UDP approximation at the runtime-traffic summary level.");

  badStruct = legacyScfg.toStruct();
badStruct.traffic = rmfield(badStruct.traffic, "flows");
badStruct.traffic = rmfield(badStruct.traffic, "targetRate_Mbps");
didError = false;
try
    sixgr.lls6g.buildInternalConfig(badStruct, fullfile(tmp, "bad"));
catch ME
    didError = contains(string(ME.identifier), "MissingResolvedConfigValue") && ...
        contains(string(ME.message), "traffic.targetRate_Mbps");
end
assert(didError, ...
    "Missing traffic.flows plus missing equivalent scalar traffic inputs must fail honestly.");

ok = true;
end
