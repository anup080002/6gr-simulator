function ok = testRecoveredPUSCHUCIEvidence()
%TESTRECOVEREDPUSCHUCIEVIDENCE Guard exact legacy-source recovery semantics.

T=table(true,1,"1","1",true,"decoded_match",true,true, ...
    "pending_feedback_table_reserved_after_pdcch_grant_binding", ...
    'VariableNames',{'UCIOnPUSCHApplied','UCIOnPUSCHFeedbackBitCount', ...
    'ExpectedHARQACKBits','DecodedHARQACKBits','HARQACKContentMatch', ...
    'HARQACKDecodeStatus','CRCApplicable','CRCPass','UCIOnPUSCHEvidenceSource'});
fixed=sixgr.truth.canonicalizeRecoveredPUSCHUCIEvidence(T);
assert(fixed.UCIOnPUSCHEvidenceRecoveryApplied && ...
    contains(string(fixed.UCIOnPUSCHEvidenceSource),"same_waveform_pusch_rx") && ...
    string(fixed.ExpectedHARQACKBits)=="1" && ...
    string(fixed.DecodedHARQACKBits)=="1", ...
    "An exact persisted receiver decode must repair only its stale source token.");

bad=T;
bad.DecodedHARQACKBits="0";
bad.HARQACKContentMatch=false;
notFixed=sixgr.truth.canonicalizeRecoveredPUSCHUCIEvidence(bad);
assert(~notFixed.UCIOnPUSCHEvidenceRecoveryApplied && ...
    string(notFixed.UCIOnPUSCHEvidenceSource)== ...
    "pending_feedback_table_reserved_after_pdcch_grant_binding", ...
    "Recovery must fail closed when persisted receiver bits do not match.");

badCRC=T;
badCRC.CRCPass=false;
notFixed=sixgr.truth.canonicalizeRecoveredPUSCHUCIEvidence(badCRC);
assert(~notFixed.UCIOnPUSCHEvidenceRecoveryApplied, ...
    "Recovery must fail closed when the canonical production CRC outcome fails.");

legacy=T(:, setdiff(string(T.Properties.VariableNames), ...
    ["CRCApplicable","CRCPass"], "stable"));
legacy.CRCError=false;
legacy=movevars(legacy,"CRCError","Before","UCIOnPUSCHEvidenceSource");
fixedLegacy=sixgr.truth.canonicalizeRecoveredPUSCHUCIEvidence(legacy);
assert(fixedLegacy.UCIOnPUSCHEvidenceRecoveryApplied, ...
    "Legacy CRCError rows remain recoverable when every receiver fact is exact.");
ok=true;
end
