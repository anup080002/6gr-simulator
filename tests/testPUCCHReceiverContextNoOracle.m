function tests = testPUCCHReceiverContextNoOracle
tests = functiontests(localfunctions);
end

function testProductionReceiverHasNoPayloadOracle(~)
source = fileread(which("sixgr.phy.ul.PUCCH_Rx"));
assert(~contains(source, "ExpectedUCIBits"), ...
    "The production PUCCH receiver still accepts transmitted payload bits.");
assert(~contains(source, "ouci = 20"), ...
    "The production PUCCH receiver still invents a 20-bit UCI payload.");
context = sixgr.phy.pucch.UCIReportContext(struct( ...
    "ReportID", "RX-CONTEXT-1", "ConfigurationEpoch", 1, ...
    "Sequence1Length", 4, "Sequence2Length", 0, ...
    "HARQACKBits", 2, "SRBits", 1, "CSIPart1Bits", 1, ...
    "CSIPart2Bits", 0, "PriorityIndex", 0));
assert(context.Sequence1Length == 4);
localAssertError(@() sixgr.phy.pucch.UCIReportContext(struct( ...
    "ReportID", "BAD", "ConfigurationEpoch", 1, ...
    "Sequence1Length", 1, "Sequence2Length", 0, ...
    "HARQACKBits", 1, "SRBits", 0, "CSIPart1Bits", 0, ...
    "CSIPart2Bits", 0, "PriorityIndex", 0, ...
    "ExpectedUCIBits", int8(1))), ...
    "sixgr:phy:pucch:OracleInputForbidden");
end

function localAssertError(fcn, expected)
observed = "";
try
    fcn();
catch ME
    observed = string(ME.identifier);
end
assert(observed == string(expected), ...
    "Expected %s, observed %s.", string(expected), observed);
end
