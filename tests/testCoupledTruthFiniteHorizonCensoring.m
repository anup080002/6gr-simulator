function ok = testCoupledTruthFiniteHorizonCensoring()
%TESTCOUPLEDTRUTHFINITEHORIZONCENSORING Preserve truncated causal events.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

state = struct();
state.CurrentSlot = 12;
state.PendingCSITable = table("DL", 1, 10, 14, false, false, ...
    "pending_causal_feedback_delay", ...
    'VariableNames', {'Direction','UEIndex','SourceSlot','DueSlot', ...
    'Processed','RightCensored','DeliveryStatus'});
state.PendingFeedbackTable = table("DL", 1, 4101, 10, 14, false, false, ...
    "terminal-feedback", "pucch", ...
    'VariableNames', {'Direction','UEIndex','RNTI','SourceSlot','DueSlot', ...
    'Processed','RightCensored','PUCCHGrantId','DeliveryMechanism'});
state.PUCCHGrantTraceTable = table("UL", "DL", 1, 4101, 10, 14, ...
    "terminal-feedback", false, false, false, false, false, "harq_ack", ...
    "scheduled_pending_execution", "PENDING", ...
    'VariableNames', {'Direction','FeedbackForDirection','UEIndex','RNTI', ...
    'SourceSlot','ScheduledAbsoluteSlot','PUCCHGrantId', ...
    'GrantExecutedFlag','MultiplexedOnPUSCH','RuntimeStateUpdated', ...
    'CanceledAtSweepBoundary','RightCensored','UCIType', ...
    'PUCCHGrantState','Status'});

state = sixgr.truth.CoupledTruthRuntime.finalizeFiniteHorizonRuntime( ...
    state, 12, "finite_runtime_horizon_reached");

assert(logical(state.PendingCSITable.RightCensored(1)) && ...
    ~logical(state.PendingCSITable.Processed(1)) && ...
    double(state.PendingCSITable.CensorBoundarySlot(1)) == 12 && ...
    string(state.PendingCSITable.CensorScope(1)) == "terminal_horizon", ...
    "Undelivered CSI must remain explicit terminal right-censored evidence.");
assert(logical(state.PendingFeedbackTable.RightCensored(1)) && ...
    ~logical(state.PendingFeedbackTable.Processed(1)), ...
    "Undelivered HARQ feedback must not be silently deleted or marked observed.");
assert(logical(state.PUCCHGrantTraceTable.RightCensored(1)) && ...
    ~logical(state.PUCCHGrantTraceTable.GrantExecutedFlag(1)) && ...
    string(state.PUCCHGrantTraceTable.Status(1)) == "RIGHT_CENSORED", ...
    "A PUCCH beyond the finite horizon must not claim waveform execution.");
assert(isempty(sixgr.truth.CoupledTruthRuntime.pucchFeedbackDueUEsRuntime( ...
    state, 14)), ...
    "Right-censored HARQ feedback must never become due after finalization.");

ok = true;
end
