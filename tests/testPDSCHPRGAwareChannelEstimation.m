function ok = testPDSCHPRGAwareChannelEstimation()
%TESTPDSCHPRGAWARECHANNELESTIMATION Guard discontinuous PRG H*W estimates.
%
% A flat physical channel does not imply a flat effective PDSCH channel
% when the precoder changes every PRG. Whole-grid DM-RS interpolation
% smears those boundaries and produces material 256QAM EVM. The truth
% receiver must estimate each PRG independently and stitch only its own
% subcarriers.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
if exist("nrPDSCHPrecode", "file") ~= 2 || exist("nrPRGInfo", "file") ~= 2
    warning("testPDSCHPRGAwareChannelEstimation:Missing5G", ...
        "Skipping because PRG precoding APIs are unavailable.");
    ok = true;
    return;
end

cfg = localConfig();
cfg.phy.pdsch.dmrs.useExactAWGNPRGEstimator = true;
carrier = nrCarrierConfig;
carrier.NCellID = 17;
carrier.NSizeGrid = 12;
carrier.NStartGrid = 0;
carrier.SubcarrierSpacing = 30;
carrier.CyclicPrefix = "normal";

pdsch = nrPDSCHConfig;
pdsch.NID = carrier.NCellID;
pdsch.RNTI = 41;
pdsch.PRBSet = 0:(carrier.NSizeGrid - 1);
pdsch.SymbolAllocation = [2 12];
pdsch.MappingType = "A";
pdsch.Modulation = "256QAM";
pdsch.NumLayers = 1;
pdsch.DMRS.DMRSConfigurationType = 1;
pdsch.DMRS.DMRSTypeAPosition = 2;
pdsch.DMRS.DMRSAdditionalPosition = 1;
pdsch.DMRS.DMRSLength = 1;
pdsch.DMRS.NumCDMGroupsWithoutData = 1;

prgInfo = nrPRGInfo(carrier, 2);
codebook = [ ...
    1, 1, 1, 1; ...
    1, 1i, -1, -1i] ./ sqrt(2);
precoderStream = RandStream("mt19937ar", "Seed", 38104);
selection = randi(precoderStream, size(codebook, 2), ...
    [1, double(prgInfo.NPRG)]);
for prg = 2:numel(selection)
    if selection(prg) == selection(prg - 1)
        selection(prg) = mod(selection(prg), size(codebook, 2)) + 1;
    end
end
assert(numel(selection) == double(prgInfo.NPRG), ...
    "Regression precoder sequence must cover every 2-RB PRG.");
W = complex(zeros(2, 1, double(prgInfo.NPRG)));
for prg = 1:double(prgInfo.NPRG)
    W(:, 1, prg) = codebook(:, selection(prg));
end

rng(38104, "twister");
[tx, ~] = sixgr.phy.dl.PDSCH_Tx(cfg, ...
    "Carrier", carrier, ...
    "PDSCH", pdsch, ...
    "TargetCodeRate", 820 / 1024, ...
    "RV", 0, ...
    "NumTxAnt", 2, ...
    "PrecodingMatrix", W, ...
    "CompactOutput", false);

% Static full-rank antenna-domain channel. Its effective rank-1 channel
% H*W changes discontinuously at every configured PRG boundary.
H = [1, 1i; 1, -1i];
rxWaveform = tx.Waveform * H.';
[rx, info] = sixgr.phy.dl.PDSCH_Rx(rxWaveform, cfg, ...
    "Carrier", carrier, ...
    "PDSCH", pdsch, ...
    "PDSCHIndices", tx.PDSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", 1e-10, ...
    "NoiseVarDomain", "grid", ...
    "CodingLayout", tx.CodingLayout, ...
    "PrecodingMatrix", W, ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true, ...
    "FastAWGNPath", false);

cfgStitched = cfg;
cfgStitched.phy.pdsch.dmrs.useExactAWGNPRGEstimator = false;
[rxStitched, infoStitched] = sixgr.phy.dl.PDSCH_Rx(rxWaveform, cfgStitched, ...
    "Carrier", carrier, ...
    "PDSCH", pdsch, ...
    "PDSCHIndices", tx.PDSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", 1e-10, ...
    "NoiseVarDomain", "grid", ...
    "CodingLayout", tx.CodingLayout, ...
    "PrecodingMatrix", W, ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true, ...
    "FastAWGNPath", false);

txSymbols = double(tx.PDSCHLayerSymbolsForEvidence(:));
rxSymbols = double(rx.LayerEqualizedSymbolsForEvidence(:));
assert(numel(rxSymbols) == numel(txSymbols), ...
    "Layer-domain Tx/Rx symbol evidence must have matching lengths.");
evmRMS = sqrt(sum(abs(rxSymbols - txSymbols).^2) ./ ...
    max(sum(abs(txSymbols).^2), eps));

assert(logical(rx.ChannelEstimatePRGAware), ...
    "Explicit PRG-bundled PDSCH must report PRG-aware channel estimation.");
assert(string(rx.ChannelEstimateEngine) == "exact_awgn_ls_per_prg_stitched" && ...
        logical(rx.ChannelEstimateExactAWGNPRGEstimatorUsed), ...
    "Eligible AWGN rank-1 PRG reception must use the exact per-PRG LS estimator.");
assert(double(rx.ChannelEstimateEstimatedPRGCount) == double(prgInfo.NPRG), ...
    "Every active PRG must have its own DM-RS-backed channel estimate.");
assert(~logical(info.ChannelEstimation.ScalarFastPathUsed), ...
    "The per-PRG estimator must not be mislabeled as a full-grid scalar shortcut.");
assert(string(infoStitched.ChannelEstimation.EngineUsed) == ...
        "nrChannelEstimate_per_prg_stitched" && ...
        ~logical(infoStitched.ChannelEstimation.ExactAWGNPRGEstimatorUsed), ...
    "Disabling the exact AWGN PRG estimator must retain the full stitched reference path.");
assert(isequal(double(info.ChannelEstimation.PRGSet(:)), ...
        double(prgInfo.PRGSet(:))), ...
    "Receiver PRG stitching must use the nrPRGInfo carrier partition.");
assert(evmRMS < 1e-3, ...
    "Near-noiseless random-PRG 256QAM EVM %.6g exceeds 0.1%%.", evmRMS);
assert(logical(rx.Ok) && ~logical(rx.CRCError), ...
    "Near-noiseless random-PRG 256QAM must pass DL-SCH CRC.");
assert(all(int8(rx.TransportBlock(:)) == int8(tx.TransportBlock(:))), ...
    "PRG-aware 256QAM reception must recover the exact transport block.");
assert(logical(rxStitched.Ok) && all(int8(rxStitched.TransportBlock(:)) == int8(tx.TransportBlock(:))), ...
    "The full stitched reference estimator must retain the same noiseless decode result.");

fastNoiseless = localMeanPRGCoefficients(rx.ChannelEstimate, prgInfo.PRGSet);
stitchedNoiseless = localMeanPRGCoefficients(rxStitched.ChannelEstimate, prgInfo.PRGSet);
noiselessDelta = localRelativeDelta(fastNoiseless, stitchedNoiseless);
assert(noiselessDelta < 1e-8, ...
    "Exact AWGN and full stitched PRG coefficients differ by %.6g in the noiseless case.", ...
    noiselessDelta);

% Feed both estimators the identical noisy waveform. The fast estimator is
% constant within a flat-AWGN PRG, so compare PRG-mean coefficients rather
% than pointwise interpolation noise.
noiseStream = RandStream("mt19937ar", "Seed", 38105);
signalPower = mean(abs(rxWaveform(:)).^2);
noiseWaveVar = signalPower .* 1e-5;
noise = sqrt(noiseWaveVar ./ 2) .* ...
    (randn(noiseStream, size(rxWaveform)) + 1i .* randn(noiseStream, size(rxWaveform)));
noisyWaveform = rxWaveform + noise;
[noiseGrid, ~] = sixgr.phy.waveform.ofdmDemodulate(carrier, noise);
noiseGridVar = mean(abs(noiseGrid(:)).^2);

[rxNoisyFast, infoNoisyFast] = localReceive(noisyWaveform, cfg, carrier, pdsch, ...
    tx, W, noiseGridVar);
[rxNoisyStitched, infoNoisyStitched] = localReceive(noisyWaveform, cfgStitched, ...
    carrier, pdsch, tx, W, noiseGridVar);
fastNoisy = localMeanPRGCoefficients(rxNoisyFast.ChannelEstimate, prgInfo.PRGSet);
stitchedNoisy = localMeanPRGCoefficients(rxNoisyStitched.ChannelEstimate, prgInfo.PRGSet);
noisyDelta = localRelativeDelta(fastNoisy, stitchedNoisy);
assert(noisyDelta < 2e-2, ...
    "Exact AWGN and full stitched PRG coefficients differ by %.6g under identical noise.", ...
    noisyDelta);
assert(logical(rxNoisyFast.Ok) && logical(rxNoisyStitched.Ok) && ...
        all(int8(rxNoisyFast.TransportBlock(:)) == int8(tx.TransportBlock(:))) && ...
        all(int8(rxNoisyStitched.TransportBlock(:)) == int8(tx.TransportBlock(:))), ...
    "Exact AWGN and full stitched estimators must preserve the same high-SNR noisy decode.");
assert(logical(infoNoisyFast.ChannelEstimation.ExactAWGNPRGEstimatorUsed) && ...
        ~logical(infoNoisyStitched.ChannelEstimation.ExactAWGNPRGEstimatorUsed), ...
    "Noisy equivalence must compare the exact AWGN engine against the full stitched engine.");

fprintf(['PDSCHPRGAwareChannelEstimation: %d PRGs, 256QAM EVM=%.6g%%, ' ...
    'noiseless delta=%.3g, noisy delta=%.3g, CRC=pass.\n'], ...
    prgInfo.NPRG, 100 .* evmRMS, noiselessDelta, noisyDelta);
ok = true;
end

function [rx, info] = localReceive(waveform, cfg, carrier, pdsch, tx, W, noiseGridVar)
[rx, info] = sixgr.phy.dl.PDSCH_Rx(waveform, cfg, ...
    "Carrier", carrier, ...
    "PDSCH", pdsch, ...
    "PDSCHIndices", tx.PDSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", noiseGridVar, ...
    "NoiseVarDomain", "grid", ...
    "CodingLayout", tx.CodingLayout, ...
    "PrecodingMatrix", W, ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true, ...
    "FastAWGNPath", false);
end

function coefficients = localMeanPRGCoefficients(Hest, prgSet)
prgSet = double(prgSet(:));
nPRG = max(prgSet);
nColumns = max(1, size(Hest, 3)) .* max(1, size(Hest, 4));
coefficients = complex(NaN(nPRG, nColumns));
for prg = 1:nPRG
    prb = find(prgSet == prg);
    subcarriers = reshape((12 .* (prb(:) - 1)) + (1:12), [], 1);
    block = Hest(subcarriers, :, :, :);
    block = reshape(block, numel(subcarriers) .* size(Hest, 2), nColumns);
    coefficients(prg, :) = mean(block, 1, "omitnan");
end
end

function delta = localRelativeDelta(actual, reference)
mask = isfinite(real(actual)) & isfinite(imag(actual)) & ...
    isfinite(real(reference)) & isfinite(imag(reference));
assert(any(mask, "all"), "PRG coefficient comparison has no finite samples.");
err = actual(mask) - reference(mask);
delta = norm(err(:)) ./ max(norm(reference(mask)), eps);
end

