function ok = testLLSULBeamPrecoderTruth()
%TESTLLSULBEAMPRECODERTRUTH Verify UL bundle exports runtime-applied PUSCH TPMI truth.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
assert(string(cfg.phy.pusch.transmissionScheme) == "codebook" && ...
    string(cfg.phy.pusch.CodebookType) == "codebook1_ng1n2n2" && ...
    double(cfg.phy.pusch.NumAntennaPorts) == 2, ...
    "The scenario YAML must explicitly select the 2-port native PUSCH " + ...
    "codebook family; the MATLAB runtime must not invent that policy.");
% Reuse the repository's YAML-owned connected PUCCH fixture; do not invent
% a MATLAB-only resource set for the DL HARQ leg exercised by the coupled
% bidirectional runtime.
pucchScfg = sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd, "simulator", "configs", "scenarios", ...
    "lls_mimo4x4_multiuser_beamformed.yaml"));
cfg.validation.pucch_resources = pucchScfg.Data.pucch_resources;
cfg.validation.pucch_resources.power_control.mu = 0;
cfg.run.numFrames = 2;
cfg.scenario.nUE = 1;
cfg.scenario.ue.nUE = 1;
cfg = sixgr.util.structSet(cfg, "lls6g.users.n_users", 1);
cfg = sixgr.util.structSet(cfg, "lls6g.users.enabled", true);
cfg = sixgr.util.structSet(cfg, "lls6g.users.execution_model", "slot_coupled_truth");
cfg = sixgr.util.structSet(cfg, "users.n_users", 1);
cfg = sixgr.util.structSet(cfg, "deployment_topology.num_ues", 1);
cfg.run.strictMode = false;
cfg.run.noProxyTruthContract = false;
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.snr_dB = 12;
cfg.run.interferenceExecutionMode = "none";
% The coupled truth bundle consumes explicit DL and UL scheduling geometry;
% this fixture must own those allocations even though it validates UL beam
% provenance only.
carrierNRB = double(sixgr.util.structGet(cfg, "phy.carrier.NSizeGrid", NaN));
assert(isfinite(carrierNRB) && carrierNRB >= 10, ...
    "UL beam fixture requires a materialized carrier grid.");
cfg.phy.bwp.dl = struct("NStartBWP", 0, "NSizeBWP", carrierNRB);
cfg.phy.bwp.ul = struct("NStartBWP", 0, "NSizeBWP", carrierNRB);
cfg.phy.pdcch.symbolAllocation = [0 2];
cfg.phy.pucch.symbolAllocation = [12 2];
cfg.phy.pdsch.prbSet = 0:9;
cfg.phy.pdsch.symbolAllocation = [2 12];
cfg.phy.pdsch.mappingType = "A";
cfg.phy.pdsch.mcsContext = struct( ...
    "UECapability1024QAM", false, ...
    "RRCEnabled1024QAM", false, ...
    "DCIEnabled1024QAM", false, ...
    "DeploymentAllows1024QAM", false, ...
    "FrequencyRangeAllows1024QAM", false, ...
    "BandAllows1024QAM", false, ...
    "FrequencyRange", "FR1", ...
    "OperatingBand", "n14", ...
    "DeploymentClass", "ul_beam_truth_fixture");
cfg.phy.pusch.prbSet = 0:9;
cfg.phy.pusch.symbolAllocation = [0 14];
cfg.phy.pusch.mappingType = "A";
cfg = sixgr.util.structSet(cfg, "phy.tddTiming.capabilityProfileID", ...
    "38.214-v18.8.0-cap1-dmrs-pos0-mu0");
cfg = sixgr.util.structSet(cfg, ...
    "phy.tddTiming.n1PDSCHProcessingTimeSymbols", 8);
cfg = sixgr.util.structSet(cfg, ...
    "phy.tddTiming.n2PUSCHPreparationTimeSymbols", 10);
if isfield(cfg.phy, "frameStructure")
    cfg.phy = rmfield(cfg.phy, "frameStructure");
end
if isfield(cfg, "resolved_runtime_view") && ...
        isfield(cfg.resolved_runtime_view, "frame_structure")
    cfg.resolved_runtime_view = rmfield( ...
        cfg.resolved_runtime_view, "frame_structure");
end
if isfield(cfg.phy, "frame")
    cfg.phy = rmfield(cfg.phy, "frame");
end
cfg = sixgr.phy.frame.FrameRuntimeStateBuilder.attachTimingContext(cfg);
cfg = sixgr.util.structSet(cfg, "run.controlGating.prachRequired", false);
cfg = sixgr.util.structSet(cfg, "run.controlGating.srsRequired", false);
cfg = sixgr.util.structSet(cfg, "run.controlGating.pdcchRequired", false);
cfg = sixgr.util.structSet(cfg, "control_gating.prach_required", false);
cfg = sixgr.util.structSet(cfg, "control_gating.srs_required", false);
cfg = sixgr.util.structSet(cfg, "control_gating.pdcch_required", false);

runFolder = fullfile(tmp, "bundle", "air_interface");
opt = struct( ...
    "LinkDuration_s", 0.001, ...
    "LinkMaxSimFrames", 2, ...
    "LinkSNR_dB", cfg.channel.snr_dB, ...
    "LinkSNRGrid_dB", cfg.channel.snr_dB, ...
    "LinkSweepFrames", 2, ...
    "LinkSweepTrialsPerSNR", 2, ...
    "LinkReferenceSweepFrames", 2, ...
    "LinkSweepMaxPoints", 1, ...
    "SaveFigures", false);
sixgr.truth.runWaveformLinkBundle(cfg, runFolder, opt);

ulCsv = fullfile(runFolder, "csv", "ul_pusch_trials.csv");
assert(exist(ulCsv, "file") == 2, ...
    "Waveform bundle must write the canonical UL raw trial CSV.");
T = readtable(ulCsv, "VariableNamingRule", "preserve");
assert(istable(T) && ~isempty(T), ...
    "Expected nonempty UL raw trial rows for requested-vs-applied beam truth validation.");

requiredVars = { ...
    'PrecoderSource','PrecodingMode','BeamformingApplied','AppliedBeamIndexSet','AppliedPrecoderPMI', ...
    'RequestedBeamIndexSet','RequestedPrecoderPMI','AppliedPrecoderSource','RequestedVsAppliedPrecoderPMIMatchStatus', ...
    'RequestedBeamTruthClassification','RequestedPrecoderPMITruthClassification', ...
    'AppliedBeamApplicationSource','AppliedBeamTruthClassification', ...
    'AppliedPrecoderPMIApplicationSource','AppliedPrecoderPMITruthClassification', ...
    'AppliedPrecoderPMIType','AppliedPrecoderCodebookMode'};
assert(all(ismember(requiredVars, T.Properties.VariableNames)), ...
    "UL raw trial CSV must expose requested/applied beam provenance fields.");

modeMask = strcmpi(string(T.PrecodingMode), "ul_codebook_tpmi");
assert(any(modeMask), ...
    "This focused UL truth test expects the active native-codebook PUSCH TPMI path.");
assert(all(strcmpi(string(T.PrecoderSource(modeMask)), "ul_pusch_native_codebook_tpmi")) && ...
    all(strcmpi(string(T.AppliedPrecoderSource(modeMask)), "ul_pusch_native_codebook_tpmi")), ...
    "UL raw trial rows must source applied PMI from native PUSCH TPMI runtime application.");
assert(all(logical(T.BeamformingApplied(modeMask))) && ...
    all(isfinite(double(T.AppliedPrecoderPMI(modeMask)))) && ...
    all(strlength(string(T.AppliedPrecoderPMIType(modeMask))) > 0) && ...
    all(strlength(string(T.AppliedPrecoderCodebookMode(modeMask))) > 0), ...
    "UL raw trial rows must materialize applied PUSCH TPMI from the waveform-applied runtime object.");
assert(all(strlength(strtrim(string(T.RequestedBeamIndexSet(modeMask)))) > 0) && ...
    all(isfinite(double(T.RequestedPrecoderPMI(modeMask)))) && ...
    all(strcmpi(string(T.RequestedBeamTruthClassification(modeMask)), "requested_reference")) && ...
    all(strcmpi(string(T.RequestedPrecoderPMITruthClassification(modeMask)), "requested_reference")) && ...
    all(strcmpi(string(T.RequestedVsAppliedPrecoderPMIMatchStatus(modeMask)), "requested_matches_runtime_applied")) && ...
    all(strcmpi(string(T.AppliedBeamTruthClassification(modeMask)), "applied_runtime_value")) && ...
    all(strcmpi(string(T.AppliedPrecoderPMITruthClassification(modeMask)), "applied_runtime_value")) && ...
    all(strcmpi(string(T.AppliedBeamApplicationSource(modeMask)), "ul_pusch_native_codebook_tpmi_port_support")) && ...
    all(strcmpi(string(T.AppliedPrecoderPMIApplicationSource(modeMask)), "ul_pusch_native_codebook_tpmi")) && ...
    all(strlength(strtrim(string(T.AppliedBeamIndexSet(modeMask)))) > 0), ...
    "UL raw trial rows must classify requested references, runtime-applied TPMI, and native PUSCH codebook port-support beam truth separately.");

ok = true;
end
