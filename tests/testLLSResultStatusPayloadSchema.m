function ok = testLLSResultStatusPayloadSchema()
%TESTLLSRESULTSTATUSPAYLOADSCHEMA Canonical result status schema is emitted.

setup6GRSimToolkit("Verbose", false);

ctx = llsRootGateFixture("pass");
verdict = sixgr.truth.evaluateLLSRuntimeTruthContract(ctx.RunFolder, ctx.ScenarioConfig, ctx.InternalConfig);

statusPath = fullfile(ctx.Layout.ReportCSVDir, "result_status_summary.csv");
assert(exist(statusPath, "file") == 2, "result_status_summary.csv must be emitted.");
T = readtable(statusPath, "VariableNamingRule", "preserve");
sixgr.truth.validateResultStatusPayload(T);
assert(logical(T.RunCompleted(1)), "RunCompleted must be true for the completed fixture.");
assert(logical(T.ArtifactsWritten(1)) && logical(T.ArtifactCompletenessOk(1)), ...
    "Artifact creation and artifact completeness must be separate passing gates.");
assert(logical(T.ResultOk(1)), "Clean strict fixture must pass the canonical ResultOk formula.");
assert(logical(verdict.Ok), "Legacy truth-contract verdict must remain aligned with canonical ResultOk for clean fixtures.");

scenarioSummary = readtable(fullfile(ctx.Layout.ReportCSVDir, "scenario_summary.csv"), ...
    "VariableNamingRule", "preserve");
assert(logical(scenarioSummary.Ok(1)) == logical(T.ResultOk(1)) && ...
    logical(scenarioSummary.ResultOk(1)) == logical(T.ResultOk(1)), ...
    "Scenario-summary root aliases must match the canonical result status.");
assert(logical(scenarioSummary.VisualArtifactIntegrityOk(1)) == ...
        logical(T.VisualArtifactGateOk(1)) && ...
    double(scenarioSummary.VisualArtifactIntegrityFailureCount(1)) == ...
        double(T.VisualArtifactFailureCount(1)), ...
    "Legacy visual-integrity summary aliases must be refreshed by terminal status reduction.");

% A functional diagnostic is not statistically qualified. The production
% reducer's NOT_EVALUATED result must reach both canonical representations,
% rather than leaving the earlier optional-gate true/NOT_APPLICABLE pair.
statistics = table("PRACH", false, false, ...
    'VariableNames', {'Component','RequiredForStandardsClaim','StatisticallyQualified'});
sixgr.util.csvWriteTable(fullfile(ctx.Layout.ReportCSVDir, ...
    "statistical_qualification_gate.csv"), statistics, "PreserveSchema", true);
qualified = sixgr.truth.applyProductionQualificationGate(verdict.ResultStatus, ctx.RunFolder);
assert(~qualified.StatisticalQualificationOk && ...
    qualified.StatisticalQualificationStatus == "NOT_EVALUATED");
sixgr.artifact.updateRootStatusArtifacts(ctx.RunFolder, qualified);
publishedCSV = sixgr.util.csvReadTable(statusPath, "TextType", "string");
publishedJSON = jsondecode(fileread(fullfile(ctx.RunFolder, ...
    "reports", "json", "result_status_summary.json")));
assert(~logical(publishedCSV.StatisticalQualificationOk(1)) && ...
    string(publishedCSV.StatisticalQualificationStatus(1)) == "NOT_EVALUATED" && ...
    ~logical(publishedJSON.StatisticalQualificationOk) && ...
    string(publishedJSON.StatisticalQualificationStatus) == "NOT_EVALUATED", ...
    'Final CSV/JSON statistical qualification must match the production reducer.');

% The normal runner also publishes an earlier artifact-only status before
% the production reducer runs. Missing optional statistical fields are not
% a request to erase a verdict already present in the canonical artifacts.
legacyUpdate = rmfield(qualified, ...
    {'StatisticalQualificationOk','StatisticalQualificationStatus'});
sixgr.artifact.updateRootStatusArtifacts(ctx.RunFolder, legacyUpdate);
preservedCSV = sixgr.util.csvReadTable(statusPath, "TextType", "string");
jsonPath = fullfile(ctx.RunFolder, "reports", "json", "result_status_summary.json");
preservedJSON = jsondecode(fileread(jsonPath));
assert(isequal(preservedCSV.StatisticalQualificationOk, ...
        publishedCSV.StatisticalQualificationOk) && ...
    isequal(preservedCSV.StatisticalQualificationStatus, ...
        publishedCSV.StatisticalQualificationStatus) && ...
    isequal(preservedJSON.StatisticalQualificationOk, ...
        publishedJSON.StatisticalQualificationOk) && ...
    isequal(preservedJSON.StatisticalQualificationStatus, ...
        publishedJSON.StatisticalQualificationStatus), ...
    'An artifact-only update must not erase the persisted statistical verdict.');

csvBefore = fileread(statusPath);
jsonBefore = fileread(jsonPath);
incompleteUpdate = rmfield(qualified, 'StatisticalQualificationStatus');
caught = false;
try
    sixgr.artifact.updateRootStatusArtifacts(ctx.RunFolder, incompleteUpdate);
catch cause
    caught = strcmp(cause.identifier, ...
        'sixgr:artifact:IncompleteStatisticalQualificationStatus');
end
assert(caught, 'A partial statistical verdict must fail before either file is written.');
assert(strcmp(fileread(statusPath), csvBefore) && ...
    strcmp(fileread(jsonPath), jsonBefore), ...
    'Invalid statistical updates must preserve both original canonical artifacts.');

% Reproduce the terminal inconsistency observed in a completed waveform
% run: the root reducer discovers a visual failure after the incoming PHY
% verdict was still green.  The finalized truth summary, root CSV/JSON and
% scenario aliases must all reduce to the same fail-closed state.
failedVisual = llsRootGateFixture("pass");
failedVisual.ScenarioConfig = sixgr.util.structSet( ...
    failedVisual.ScenarioConfig, "validation.required_artifact_audit", true);
integrity = table("unit_plot", "reports/image/unit_plot.png", false, ...
    "unmanifested_visual_artifact", "runtime plot lacks canonical lineage", ...
    'VariableNames', {'PlotId','ArtifactPath','IntegrityOk','FailureCode','FailureReason'});
semantic = table("unit_plot", false, "lineage_missing", ...
    "runtime plot lacks source binding", ...
    'VariableNames', {'plot_id','audit_ok','failure_code','failure_reason'});
sixgr.util.csvWriteTable(fullfile(failedVisual.Layout.ReportCSVDir, ...
    "visual_artifact_integrity.csv"), integrity);
sixgr.util.csvWriteTable(fullfile(failedVisual.Layout.ReportCSVDir, ...
    "visual_artifact_audit.csv"), semantic);
failedVerdict = sixgr.truth.evaluateLLSRuntimeTruthContract( ...
    failedVisual.RunFolder, failedVisual.ScenarioConfig, ...
    failedVisual.InternalConfig);
failedRoot = readtable(fullfile(failedVisual.Layout.ReportCSVDir, ...
    "result_status_summary.csv"), "VariableNamingRule", "preserve");
failedTruth = readtable(fullfile(failedVisual.Layout.ReportCSVDir, ...
    "truth_contract_summary.csv"), "VariableNamingRule", "preserve");
failedSummary = readtable(fullfile(failedVisual.Layout.ReportCSVDir, ...
    "scenario_summary.csv"), "VariableNamingRule", "preserve");
assert(~logical(failedVerdict.RuntimeTruthContractOk) && ...
    ~logical(failedRoot.TruthContractOk(1)) && ...
    ~logical(failedRoot.RuntimeTruthContractOk(1)) && ...
    ~logical(failedTruth.RuntimeTruthContractOk(1)), ...
    "Terminal visual failure must not leave the canonical root truth status green.");
assert(double(failedRoot.VisualArtifactFailureCount(1)) == 2 && ...
    double(failedSummary.VisualArtifactIntegrityFailureCount(1)) == 2, ...
    "Root and scenario summaries must retain the exact terminal visual failure count.");

ok = true;
end
