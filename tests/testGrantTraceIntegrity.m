function ok = testGrantTraceIntegrity()
%TESTGRANTTRACEINTEGRITY Guard grant-table semantics and proxy-quarantine behavior.

setup6GRSimToolkit("Verbose", false);
repoRoot = fileparts(which("setup6GRSimToolkit"));

badGrant = struct( ...
    "Direction", "DL", ...
    "RNTI", 1, ...
    "PRBSet", 0:1, ...
    "SymbolAllocation", [0 2], ...
    "Modulation", "QPSK", ...
    "NumLayers", 1, ...
    "TBSBits", 5000, ...
    "TBSBytes", 625);
threwImpossible = false;
try
    sixgr.util.resolveGrantTBSBits(badGrant, "test impossible grant");
catch ME
    threwImpossible = contains(string(ME.identifier), "GrantTBS:ImpossibleValue");
end
assert(threwImpossible, "Grant TBS validator must reject values above the loose allocation upper bound.");

assert(exist(fullfile(repoRoot, "+sixgr", "+system", "buildFastProxyTraceArtifacts.m"), "file") == 0, ...
    "Fast proxy trace builder source should be removed from the repo.");

cfg = sixgr.config.defaultConfig();
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmp, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", 0.02, ...
    "E2EMaxSlots", 24, ...
    "E2EUECount", 2, ...
    "E2ETrafficModel", "xr", ...
    "E2EAirModel", "truth", ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", false, ...
    "GenerateCampaignPlots", false, ...
    "E2EStrictValidation", false);

assert(isfield(rep, "E2E") && istable(rep.E2E.SlotTable) && ~isempty(rep.E2E.SlotTable), ...
    "Truth E2E path must still export slot-level aggregate metrics.");
assert(istable(rep.E2E.PacketTraceTable), ...
    "Truth E2E path must expose packet trace output.");
assert(istable(rep.E2E.SchedulerTraceTable), ...
    "Truth E2E path must expose scheduler trace output.");
assert(istable(rep.E2E.HARQTraceTable), ...
    "Truth E2E path must expose HARQ trace output.");
if ~isempty(rep.E2E.SchedulerTraceTable)
    if ismember("TBSBits", string(rep.E2E.SchedulerTraceTable.Properties.VariableNames))
        assert(all(isfinite(double(rep.E2E.SchedulerTraceTable.TBSBits))), ...
            "Truth scheduler trace must keep finite grant-level TBSBits.");
    end
end
assert(lower(string(rep.E2E.SummaryTable.ExecutionBackend(1))) == "full_stack_replay_system_coupled", ...
    "Regression must remain on the waveform truth E2E backend.");

ok = true;
end
