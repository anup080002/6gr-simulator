function ok = testE2E_QoSvsSemanticReporting()
%TESTE2E_QOSVSSEMANTICREPORTING Semantic/accounting correctness must not imply QoS pass.

setup6GRSimToolkit("Verbose", false);
tmp = fullfile(pwd,'results','sls','qos_vs_semantic_reporting', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(tmp);
fprintf('QOS_VS_SEMANTIC_EVIDENCE_ROOT=%s\n',tmp);
[cfg,nSlots] = e2eReceivedAccessConfig(tmp,3,"xr");
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.run.seed = 41;
cfg.traffic.packetDelayBudget_ms = 0.1;
cfg.traffic.flows.packetDelayBudget_ms = 0.1;
cfg.traffic.rlcSduChunk_bytes = 512;

save(fullfile(tmp,'test_configuration.mat'),'cfg','nSlots');

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmp, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", nSlots*sixgr.time.slotDurationSec(cfg), ...
    "E2EMaxSlots", nSlots, ...
    "E2ETruthMaxSlots", nSlots, ...
    "E2EUECount", 3, ...
    "E2ETrafficModel", "xr", ...
    "E2EAirModel", "truth", ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", false, ...
    "GenerateCampaignPlots", false, ...
    "E2EStrictValidation", false);

save(fullfile(tmp,'test_output.mat'),'rep','-v7.3');
assert(height(rep.E2E.ReceivedAccessBindings)==3, ...
    'QoS reporting must retain actual access for all three UEs.');
G = rep.E2E.SchedulerTraceTable;
assert(~isempty(G) && all(ismember(["DL","UL"],upper(string(G.Direction)))), ...
    'QoS reporting requires executed grants in both directions.');
S = rep.E2E.SummaryTable(1,:);
P = rep.E2E.PacketIntegrityTable;
Q = rep.E2E.QoSEvaluationTable;
assert(all(ismember(["DL","UL"],upper(string(P.Direction(P.GeneratedPackets>0))))), ...
    'Both original traffic populations must contain generated packets.');

assert(all(logical(P.AccountingIntegrityPass)), "Packet accounting should remain clean in this QoS-failure regression.");
assert(double(S.PacketAccountingPassRate_pct) >= 99.9, "Packet-accounting pass rate should stay high.");
assert(~logical(S.QoSPass), "QoS should fail when service quality is poor.");
assert(~logical(S.LatencyBudgetPass) || ~logical(S.DeliveryRatioPass) || ~logical(S.ThroughputTargetPass), ...
    "At least one QoS dimension must fail in this regression.");
assert(istable(Q) && height(Q) >= 3, "QoS evaluation table must be exported.");
allRow = Q(upper(string(Q.Direction)) == "ALL", :);
assert(height(allRow) == 1, "QoS evaluation table must include an ALL row.");
assert(logical(allRow.Evaluated), "ALL QoS row must be evaluated.");
assert(~logical(allRow.QoSPass), "ALL QoS row must fail in this regression.");

layout = sixgr.report.resultLayout(char(string(rep.Summary.RunFolder)));
md = fileread(layout.CampaignReportMD);
assert(contains(md, "Packet-accounting integrity pass rate"), "Markdown report must mention packet-accounting integrity.");
assert(contains(md, "QoS/SLA acceptance"), "Markdown report must mention QoS/SLA acceptance.");
assert(contains(md, "execution/report integrity can pass while QoS/SLA acceptance fails"), ...
    "Markdown report must explain the integrity-vs-QoS distinction.");

ok = true;
end
