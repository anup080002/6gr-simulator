function summary = runPhase26FocusedTests()
%RUNPHASE26FOCUSEDTESTS Run only the bounded wiring-gate regressions.

names = { ...
    'testQuickPlus20SameChainYAMLAuthority', ...
    'testQuickPlus20WiringGateYAMLAuthority', ...
    'testLLSMeasurementSidecarIntegrity', ...
    'testSchedulerOLLADbMarginMapping', ...
    'testLLSStatisticalQualificationGate', ...
    'testArtifactContractEngine', ...
    'testMIMOFrequencySelectiveSpatialSignature', ...
    'testCSIRuntimeExecution', ...
    'testPhase7CampaignEvidenceGates', ...
    'testScenarioCSVAnnotationRuntimeIsolation', ...
    'testMatSaveFilesystemAtomic', ...
    'testSIB1ToFourStepRAIntegration'};

passed = false(numel(names), 1);
elapsed_s = zeros(numel(names), 1);
identifiers = strings(numel(names), 1);
messages = strings(numel(names), 1);
for k = 1:numel(names)
    fprintf('FOCUSED_START %s\n', names{k});
    timer = tic;
    try
        feval(names{k});
        passed(k) = true;
        elapsed_s(k) = toc(timer);
        fprintf('FOCUSED_PASS %s %.3fs\n', names{k}, elapsed_s(k));
    catch exception
        elapsed_s(k) = toc(timer);
        identifiers(k) = string(exception.identifier);
        messages(k) = string(exception.message);
        fprintf(2, 'FOCUSED_FAIL %s %s | %s\n', names{k}, ...
            char(identifiers(k)), char(messages(k)));
    end
end

summary = table(string(names(:)), passed, elapsed_s, identifiers, messages, ...
    'VariableNames', {'Test', 'Passed', 'Elapsed_s', 'Identifier', 'Message'});
fprintf('FOCUSED_SUMMARY pass=%d fail=%d total=%d\n', ...
    nnz(passed), nnz(~passed), numel(names));
if any(~passed)
    disp(summary(~passed, :));
    error('sixgr:focused:Failure', '%d focused test(s) failed.', nnz(~passed));
end
end
