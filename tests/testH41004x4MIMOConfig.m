function ok = testH41004x4MIMOConfig()
%TESTH41004X4MIMOCONFIG Lock the H4 64-TXRU / four-chain UE contract.

setup6GRSimToolkit("Verbose", false);

scenarioFiles = [ ...
    "h4_100_a0_fixed_mcs.yaml"
    "h4_100_tdla30_fixed_mcs.yaml"
    "h4_100_cdlc100_fixed_mcs.yaml"
    "h4_100_tdla30_connected_adaptive.yaml"
    "h4_100_cdlc100_connected_adaptive.yaml"];

for scenarioOrdinal = 1:numel(scenarioFiles)
    scenarioPath = fullfile("simulator", "configs", "scenarios", ...
        scenarioFiles(scenarioOrdinal));
    scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
    configuredDCIFormats = string(scfg.get("control.dci_formats"));
    configuredDCIFormats = configuredDCIFormats(:);
    configuredDCIFamilies = string(scfg.get("pdcch.dci_families"));
    configuredDCIFamilies = configuredDCIFamilies(:);
    configuredCSIRSPortSet = double(scfg.get( ...
        "reference_signals.nzp_csi_rs.port_set"));
    configuredCSIRSPortSet = configuredCSIRSPortSet(:).';
    assert(isequal(configuredDCIFormats, ...
        ["0_1"; "1_1"]) && ...
        isequal(configuredDCIFamilies, ...
        ["0_1"; "1_1"]) && ...
        string(scfg.get("pdcch.dci_format_dl")) == "1_1" && ...
        string(scfg.get("pdcch.dci_format_ul")) == "0_1", ...
        ["H4 connected monitoring metadata must retain both Release-18 " ...
         "UE-specific DCI directions; Type-0 DCI 1_0 is derived locally."]);
    assert(string(scfg.get("prach.format")) == "B4" && ...
        string(scfg.get("prach.long_short_preamble_mode")) == "short", ...
        "H4 PRACH format B4 must be identified as an L_RA=139 short preamble.");
    assert(double(scfg.get("reference_signals.nzp_csi_rs.num_ports")) == 4 && ...
        isequal(configuredCSIRSPortSet, 0:3) && ...
        double(scfg.get("reference_signals.nzp_csi_rs.periodicity_slots")) == 20 && ...
        string(scfg.get("reference_signals.nzp_csi_rs.periodicity")) == "10ms", ...
        ["The exported NZP CSI-RS descriptor must match the executable " ...
         "four-port, 20-slot mu-1 resource calendar."]);
    assert(double(scfg.get("reference_signals.trs.periodicity_slots")) == 20 && ...
        string(scfg.get("reference_signals.trs.periodicity")) == "20", ...
        ["The exported TRS descriptor must match the executable 20-slot " ...
         "tracking calendar."]);
    assert(double(scfg.get( ...
        "csi_acquisition_and_reporting.csi_report_periodicity_slots")) == 20 && ...
        double(scfg.get( ...
        "csi_acquisition_and_reporting.csi_report_offset_slots")) == 13 && ...
        string(scfg.get( ...
        "csi_acquisition_and_reporting.report_periodicity")) == "10ms", ...
        ["H4 periodic CSI must not inherit the old five-slot short-fixture " ...
         "calendar; its report belongs on the causal special-slot PUCCH occasion."]);
    cfg = sixgr.lls6g.buildInternalConfig(scfg, ...
        fullfile(tempdir, "h4_100_4x4_config", string(scenarioOrdinal)));

    rowNumbers = double(sixgr.util.structGet(cfg, ...
        "phy.csirs.rowNumbers", []));
    subcarrierLocations = double(sixgr.util.structGet(cfg, ...
        "phy.csirs.subcarrierLocationsByResource", []));
    symbolLocations = double(sixgr.util.structGet(cfg, ...
        "phy.csirs.symbolLocationsByResource", []));
    assert(isequal(rowNumbers(:).', repmat(4, 1, 8)), ...
        "H4 must configure four-port CSI-RS row 4 for all eight beam resources.");
    assert(isequal(subcarrierLocations(:).', zeros(1, 8)), ...
        ["Every H4 row-4 CSI-RS resource must preserve its configured " ...
         "TS 38.211 k0 location."]);
    assert(isequal(symbolLocations(:).', [3 4 5 6 8 9 10 12]), ...
        "H4 CSI-RS resources must avoid the configured PDSCH DMRS symbols.");

    assert(isequal(double(cfg.phy.bsArray), [4 4 2 2 1]), ...
        "The two-panel gNB must resolve to 4x4 spatial positions, H/V and two panels.");
    assert(isequal(double(cfg.phy.ueArray), [1 2 2 1 1]), ...
        "The four-chain UE must resolve to two spatial positions with H/V polarization.");
    assert(double(cfg.phy.nTxAnt) == 64 && double(cfg.phy.nRxAnt) == 4, ...
        "The installed downlink channel must be 64-by-4 element-domain MIMO.");
    assert(double(cfg.phy.pdsch.numAntennaPorts) == 4 && ...
        double(cfg.phy.pdsch.maxRankDefault) == 4, ...
        "The gNB must expose four logical DL ports with rank capped at four.");
    assert(double(cfg.phy.pusch.numAntennaPorts) == 4 && ...
        double(cfg.phy.pusch.maxRankDefault) == 4, ...
        "The UE must expose four logical UL ports with rank capped at four.");
    assert(double(cfg.phy.srs.nPorts) == 4, ...
        "Four-chain UL rank adaptation requires four independently mapped SRS ports.");
    assert(string(cfg.antenna.bs.element.model) == "3gpp_tr38901" && ...
        string(cfg.antenna.ue.element.model) == "3gpp_tr38901" && ...
        cfg.antenna.bs.requireElementPatternInChannel && ...
        cfg.antenna.ue.requireElementPatternInChannel, ...
        "H4 must install its YAML-resolved TR 38.901 H/V element patterns " + ...
        "on both runtime channel endpoints.");
    assert(~logical(cfg.mac.scheduler.fastNREApprox) && ...
        any(strcmpi(string(cfg.mac.scheduler.tbsMode), ["faithful","strict"])), ...
        "H4 grants must use exact nrTBS resource accounting, not fast NRE approximation.");

    srIdentity = struct( ...
        "UEID", 1, "RNTI", double(cfg.phy.pdsch.RNTI), ...
        "ServingCell", 1, "PUCCHCell", 1, ...
        "ComponentCarrier", double(cfg.phy.frame.DefaultIdentity.ScheduledCCID), ...
        "ActiveULBWP", double(cfg.phy.frame.DefaultIdentity.ULBWPID));
    srCalendar = sixgr.truth.buildConfiguredSRCalendar(cfg, srIdentity, 1, 20);
    assert(~isempty(srCalendar) && all(srCalendar.PeriodSlots == 5) && ...
        all(srCalendar.OffsetSlots == 3), ...
        "The 30-kHz H4 UE must explicitly support its additional sl5 SR " + ...
        "period and retain the special-slot symbol allocation.");

    csiIdentity = struct( ...
        "UEID", 1, "RNTI", double(cfg.phy.pdsch.RNTI), ...
        "ServingCell", 1, "PUCCHCell", 1, ...
        "ComponentCarrier", double(cfg.phy.frame.DefaultIdentity.ScheduledCCID), ...
        "ActiveULBWP", double(cfg.phy.frame.DefaultIdentity.ULBWPID));
    csiCalendar = sixgr.truth.buildPeriodicCSIReportObligations( ...
        cfg, csiIdentity, 1, 60);
    assert(isequal(csiCalendar.ReportSlot, [14; 34; 54]) && ...
        isequal(csiCalendar.CSIReferenceSlot, [4; 24; 44]) && ...
        all(csiCalendar.ULResourceAvailable) && ...
        all(csiCalendar.ResourceBlocker == ""), ...
        ["H4 CSI reports must use the 20-slot special-slot calendar and a " ...
         "causal TS 38.214 reference window; no report may be forced into " ...
         "the inherited slot-4 occasion."]);

    precoders = cfg.phy.csirs.precoderMatrices;
    assert(isequal(size(precoders), [64 4 8]), ...
        "The CSI-RS codebook must contain eight 64-by-4 physical beam states.");
    assert(~isfield(cfg.phy.csirs, "precoderPanelIndices"), ...
        ["H4 logical CSI ports must not be pinned to one physical panel; " ...
         "each port is distributed over the dual-panel array."]);
    for resourceOrdinal = 1:size(precoders, 3)
        W = precoders(:,:,resourceOrdinal);
        assert(norm(W' * W - eye(4), "fro") < 1e-10, ...
            "Each four-port CSI-RS physical precoder must be orthonormal.");
        assert(norm(W(1:32,:) - W(33:64,:), "fro") < 1e-12 && ...
            abs(norm(W(1:32,:), "fro")^2 - 2) < 1e-12 && ...
            abs(norm(W(33:64,:), "fro")^2 - 2) < 1e-12, ...
            ["Every logical CSI-RS port must be coherently distributed " ...
             "with equal power over both physical panels."]);
    end

    reportRequest = cfg.phy.csi.reportConfiguration;
    assert(string(reportRequest.CodebookType) == "typeI-SinglePanel" && ...
        double(reportRequest.Ports) == 4 && double(reportRequest.Panels) == 1 && ...
        isequal(double(reportRequest.AllowedRanks), [1 2 4]), ...
        ["H4 must use the qualified four-port Type-I Single-Panel wire " ...
         "schema without relabeling the dual-panel physical precoder."]);
    for reportedRank = [1 2 4]
        rankRequest = reportRequest;
        rankRequest.Rank = reportedRank;
        wire = sixgr.phy.mimo.CSIReportConfiguration( ...
            rankRequest, double(rankRequest.Epoch));
        wire.assertQualifiedWireLayout();
    end

    carrier = nrCarrierConfig;
    carrier.NCellID = cfg.phy.carrier.NCellID;
    carrier.SubcarrierSpacing = cfg.phy.carrier.SubcarrierSpacing;
    carrier.NSizeGrid = cfg.phy.carrier.NSizeGrid;
    carrier.NStartGrid = cfg.phy.carrier.NStartGrid;
    carrier.NFrame = 0;
    carrier.NSlot = 2;
    scheduledCfg = sixgr.util.structSet(cfg, ...
        "lls6g.runtime.AbsoluteSlotIndex0", 2);
    [indices, symbols, csirsInfo] = sixgr.phy.refsig.csirs( ...
        carrier, scheduledCfg, "IndexBase", "1based");
    assert(~isempty(indices) && numel(indices) == numel(symbols), ...
        "The scheduled H4 CSI-RS occasion must materialize physical REs.");
    assert(csirsInfo.NumResources == 8 && ...
        all([csirsInfo.Resources.NumPorts] == 4), ...
        "The H4 CSI-RS occasion must retain eight resources with four ports each.");
    for resourceOrdinal = 1:8
        assert(isequal( ...
            csirsInfo.Resources(resourceOrdinal).SubcarrierLocations, ...
            0), ...
            "H4 CSI-RS resource %d lost its row-4 k0 placement.", ...
            resourceOrdinal - 1);
    end
end

% The exact H4 panel has mathematical array nulls on the requested angular
% sampling grid.  MATLAB represents zero linear directivity as -Inf dBi.
% Verify the same 64-TXRU/four-chain runtime objects used by the scenario
% retain those nulls without accepting NaN or +Inf corruption.
sweepScenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    "simulator", "configs", "scenarios", ...
    "h4_100_cdlc100_connected_impaired_snr_sweep.yaml"));
sweepCfg = sixgr.lls6g.buildInternalConfig(sweepScenario, ...
    fullfile(tempdir, "h4_100_runtime_pattern_config"));
bsRuntime = sixgr.rf.AntennaArrayFactory.build(sweepCfg, "bs", ...
    "signal", "pdsch", "numPorts", 4, "numRFChains", 64);
ueRuntime = sixgr.rf.AntennaArrayFactory.build(sweepCfg, "ue", ...
    "signal", "pdsch", "numPorts", 4, "numRFChains", 4);
assert(isa(bsRuntime.ElementObj, "phased.NRAntennaElement") && ...
    isa(ueRuntime.ElementObj, "phased.NRAntennaElement"), ...
    "The H4 runtime must not silently replace configured TR 38.901 elements with isotropic elements.");
patternT = sixgr.truth.buildRuntimeAntennaPatternSampleTable(sweepCfg, ...
    struct("Antenna", bsRuntime, "Metadata", struct( ...
        "NodeType", "BS", "NodeIndex", 1, "BaseStationID", 1)), ...
    struct("Antenna", ueRuntime, "Metadata", struct( ...
        "NodeType", "UE", "NodeIndex", 1, "UEIndex", 1)));
assert(~isempty(patternT) && ...
    ~any(isnan(patternT.Directivity_dBi) | patternT.Directivity_dBi==Inf) && ...
    any(isfinite(patternT.Directivity_dBi)), ...
    "H4 runtime pattern evidence must reject NaN and +Inf while retaining real TR 38.901 samples.");

% Exact array nulls are easiest to reproduce with the same dual-polarized
% panel geometry and isotropic elements.  This is a component regression,
% not the H4 scenario configuration: its purpose is to lock the valid
% logarithmic -Inf representation rather than silently clamp it.
nullCfg = sixgr.util.structSet(sweepCfg, "antenna.bs.element.model", "isotropic");
nullCfg = sixgr.util.structSet(nullCfg, "antenna.ue.element.model", "isotropic");
nullCfg = sixgr.util.structSet(nullCfg, "antenna.bs.requireElementPatternInChannel", false);
nullCfg = sixgr.util.structSet(nullCfg, "antenna.ue.requireElementPatternInChannel", false);
nullBS = sixgr.rf.AntennaArrayFactory.build(nullCfg, "bs", ...
    "signal", "pdsch", "numPorts", 4, "numRFChains", 64);
nullUE = sixgr.rf.AntennaArrayFactory.build(nullCfg, "ue", ...
    "signal", "pdsch", "numPorts", 4, "numRFChains", 4);
nullT = sixgr.truth.buildRuntimeAntennaPatternSampleTable(nullCfg, ...
    struct("Antenna", nullBS, "Metadata", struct( ...
        "NodeType", "BS", "NodeIndex", 1, "BaseStationID", 1)), ...
    struct("Antenna", nullUE, "Metadata", struct( ...
        "NodeType", "UE", "NodeIndex", 1, "UEIndex", 1)));
assert(any(nullT.Directivity_dBi==-Inf) && ...
    ~any(isnan(nullT.Directivity_dBi) | nullT.Directivity_dBi==Inf), ...
    "The exact-null component must preserve -Inf dBi and reject NaN or +Inf.");

ok = true;
end
