function ok = testTargetHARQDiagnosticAtomicRankTransition()
%TESTTARGETHARQDIAGNOSTICATOMICRANKTRANSITION Reproduce bundle-tail state.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile(pwd, ...
    "simulator", "configs", "scenarios", ...
    "webgui_sinr_sweep_64x4_mu_mimo_full.yaml"));
tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() localCleanup(tmp)); %#ok<NASGU>
cfg = sixgr.lls6g.buildInternalConfig(scenario, fullfile(tmp, "run"));

assert(double(sixgr.util.structGet(cfg, "phy.pdsch.numLayers", NaN)) == 2, ...
    "Target HARQ regression requires configured DL rank 2.");
cfg = sixgr.util.structSet(cfg, "phy.pdsch.precoding.matrix", eye(2));
cfg = sixgr.util.structSet(cfg, "phy.pdsch.precodingMatrix", []);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.W", []);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.numPorts", 2);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.nPorts", 2);

opt = struct( ...
    "LinkSNR_dB", 20, ...
    "LinkSNRGrid_dB", 20, ...
    "LinkSweepFrames", 1, ...
    "LinkSweepMaxPoints", 1, ...
    "HARQLivePreview", true, ...
    "HARQProbeDirections", "DL", ...
    "HARQProbePackets", 1);
artifacts = sixgr.truth.exportLLSHARQDiagnostics( ...
    cfg, fullfile(tmp, "run", "air_interface"), opt);
assert(istable(artifacts.PacketTable) && ~isempty(artifacts.PacketTable), ...
    "Target rank-2 HARQ bundle-tail probe emitted no waveform evidence.");
assert(all(string(artifacts.PacketTable.Direction) == "DL"), ...
    "Target HARQ regression emitted an unexpected direction.");
ok = true;
end

function localCleanup(pathText)
if isfolder(pathText)
    rmdir(pathText, "s");
end
end
