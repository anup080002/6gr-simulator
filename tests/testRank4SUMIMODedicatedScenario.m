function result = testRank4SUMIMODedicatedScenario()
%TESTRANK4SUMIMODEDICATEDSCENARIO Execute and gate one true rank-4 SU-MIMO TB.

repoRoot = fileparts(fileparts(mfilename("fullpath")));
configPath = fullfile(repoRoot, "configs", "lls", ...
    "pdsch_cdlc_rank4_256qam_ptrs_regression.yaml");
outputRoot = fullfile(repoRoot, "results", "lls", ...
    "ran1_waveform_qualification");
runTag = "pdsch_cdlc_rank4_su_mimo_4stream_20260810_02";

result = sixgr.lls.runLLS(configPath, ...
    "OutputRoot", outputRoot, ...
    "RunTag", runTag, ...
    "GeneratePlots", true);

trials = result.TrialTable;
assert(string(result.Status) == "complete_valid", ...
    "sixgr:lls:Rank4SUMIMOStatus", ...
    "Dedicated SU-MIMO run status was %s.", string(result.Status));
assert(height(trials) == 1, ...
    "sixgr:lls:Rank4SUMIMOTrialCount", ...
    "Expected exactly one actual transport-block trial, observed %d.", ...
    height(trials));
assert(all(double(trials.NumLayers) == 4) && ...
       all(double(trials.NumTxPorts) == 4) && ...
       all(double(trials.NumRxAntennas) == 4), ...
    "sixgr:lls:Rank4SUMIMORankCollapse", ...
    "Configured rank/stream/antenna dimensions did not reach the waveform chain.");
assert(all(string(trials.Modulation) == "256QAM") && ...
       all(string(trials.MCSTable) == "calibration_explicit"), ...
    "sixgr:lls:Rank4SUMIMOMCSMismatch", ...
    "Configured modulation or fixed-MCS provenance was not executed.");
assert(all(double(trials.PTRSRE) > 0), ...
    "sixgr:lls:Rank4SUMIMOMissingPTRS", ...
    "PT-RS was enabled but produced no physical resource elements.");
assert(all(trials.TrueChannelGridAvailable) && ...
       all(string(trials.ChannelModel) == "CDL-C"), ...
    "sixgr:lls:Rank4SUMIMOMissingChannelTruth", ...
    "CDL-C per-resource truth channel evidence is missing.");
assert(all(~trials.CRCError), ...
    "sixgr:lls:Rank4SUMIMOCRCFailure", ...
    "The rank-4 SU-MIMO transport block failed CRC.");
assert(all(result.ValidityTable.Pass), ...
    "sixgr:lls:Rank4SUMIMOValidityFailure", ...
    "One or more dedicated result-validity checks failed.");

fprintf(["SU_MIMO_PASS status=%s trials=%d rank=%d tx=%d rx=%d " + ...
    "modulation=%s ptrs_re=%d crc_error=%d output=%s\n"], ...
    string(result.Status), height(trials), double(trials.NumLayers(1)), ...
    double(trials.NumTxPorts(1)), double(trials.NumRxAntennas(1)), ...
    string(trials.Modulation(1)), double(trials.PTRSRE(1)), ...
    double(trials.CRCError(1)), string(result.RunFolder));
end
