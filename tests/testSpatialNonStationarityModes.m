function ok = testSpatialNonStationarityModes()
%TESTSPATIALNONSTATIONARITYMODES Verify explicit spatial non-stationarity modes stay honest.

setup6GRSimToolkit("Verbose", false);

cfgLegacy = sixgr.config.defaultConfig();
cfgLegacy.channel.spatialNonStationary.enable = true;
cfgLegacy.channel.spatialNonStationary.numTxSubarrays = 3;
cfgLegacy.channel.spatialNonStationary.numRxSubarrays = 2;
cfgLegacy.channel.spatialNonStationary.pVisible = 0.5;

legacy = sixgr.channel.SpatialNonStationarity(cfgLegacy, "NumTxAnt", 8, "NumRxAnt", 4, "Seed", 5);
assert(strcmpi(char(string(legacy.mode)), "legacy_random_mask_placeholder") && ...
    logical(legacy.placeholderUsed) && ...
    strcmpi(char(string(legacy.visibilityMaskSource)), "legacy_random_mask_placeholder") && ...
    strcmpi(char(string(legacy.complianceStatus)), "placeholder"), ...
    "Enabled spatial non-stationarity must default to the explicitly labeled legacy placeholder mode.");

cfgBlocked = cfgLegacy;
cfgBlocked.channel.spatialNonStationary.mode = "geometry_based_visibility";
blocked = sixgr.channel.SpatialNonStationarity(cfgBlocked, "NumTxAnt", 8, "NumRxAnt", 4, "Seed", 7);
assert(strcmpi(char(string(blocked.mode)), "geometry_based_visibility") && ...
    strcmpi(char(string(blocked.valueStatus)), "blocked_missing_geometry_inputs") && ...
    strcmpi(char(string(blocked.visibilityMaskSource)), "blocked_missing_geometry_inputs") && ...
    ~logical(blocked.placeholderUsed) && ...
    ~any(blocked.txMask(:)) && ~any(blocked.rxMask(:)), ...
    "Geometry mode must block cleanly when the required runtime geometry inputs are missing.");

txMeta = struct( ...
    "NumRows", 2, ...
    "NumCols", 4, ...
    "SpacingH_lambda", 0.5, ...
    "SpacingV_lambda", 0.5, ...
    "Azimuth_deg", 30);
rxMeta = struct( ...
    "NumRows", 4, ...
    "NumCols", 1, ...
    "SpacingH_lambda", 0.5, ...
    "SpacingV_lambda", 0.5, ...
    "Heading_deg", -15);

cfgGeomA = cfgBlocked;
cfgGeomA.channel.spatialNonStationary.relativeBearing_deg = 10;
geomA = sixgr.channel.SpatialNonStationarity(cfgGeomA, ...
    "NumTxAnt", 8, "NumRxAnt", 4, "Seed", 9, ...
    "TransmitAntennaMeta", txMeta, "ReceiveAntennaMeta", rxMeta);
cfgGeomB = cfgGeomA;
cfgGeomB.channel.spatialNonStationary.relativeBearing_deg = 70;
geomB = sixgr.channel.SpatialNonStationarity(cfgGeomB, ...
    "NumTxAnt", 8, "NumRxAnt", 4, "Seed", 9, ...
    "TransmitAntennaMeta", txMeta, "ReceiveAntennaMeta", rxMeta);

assert(strcmpi(char(string(geomA.valueStatus)), "geometry_backed_proxy") && ...
    strcmpi(char(string(geomA.visibilityMaskSource)), "geometry_based_visibility_proxy") && ...
    strcmpi(char(string(geomA.complianceStatus)), "geometry_based_proxy") && ...
    ~logical(geomA.placeholderUsed), ...
    "Geometry mode must disclose that it is a geometry-backed proxy rather than a placeholder.");
assert(~isequal(geomA.txMask, geomB.txMask) || ~isequal(geomA.rxMask, geomB.rxMask), ...
    "Changing the relative-bearing geometry input must change the visibility masks in geometry mode.");

cfgFactory = sixgr.config.defaultConfig();
cfgFactory.channel.model = "TR38901";
cfgFactory.channel.pathlossModel = "ABG";
cfgFactory.channel.pathloss.model = "ABG";
cfgFactory.channel.complianceMode = "approximate_38901_plus";
cfgFactory.channel.spatialNonStationary.enable = true;
cfgFactory.channel.spatialNonStationary.mode = "geometry_based_visibility";
cfgFactory.channel.spatialNonStationary.relativeBearing_deg = 25;
cfgFactory.channel.nTxAnt = 8;
cfgFactory.channel.nRxAnt = 4;

ch = sixgr.channel.ChannelFactory.create(cfgFactory, ...
    "Model", "TR38901", ...
    "NumTxAnt", 8, ...
    "NumRxAnt", 4, ...
    "TransmitAntennaMeta", txMeta, ...
    "ReceiveAntennaMeta", rxMeta, ...
    "Seed", 11);

assert(strcmpi(char(string(ch.Meta.SpatialNonStationarityMode)), "geometry_based_visibility") && ...
    strcmpi(char(string(ch.Meta.VisibilityMaskSource)), "geometry_based_visibility_proxy") && ...
    strcmpi(char(string(ch.Meta.SpatialNonStationarityComplianceStatus)), "geometry_based_proxy") && ...
    ~logical(ch.Meta.PlaceholderUsed), ...
    "ChannelFactory metadata must preserve the resolved spatial non-stationarity mode and source.");

ok = true;
end
