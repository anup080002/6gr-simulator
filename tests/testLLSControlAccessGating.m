function ok = testLLSControlAccessGating()
%TESTLLSCONTROLACCESSGATING Focused LLS control/access gating checks.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
cfg = sixgr.util.structSet(cfg, "run.controlGating.trsRequired", false);
cfg = sixgr.util.structSet(cfg, "control_gating.trs_required", false);
cfg = sixgr.util.structSet(cfg, "phy.duplex.mode", "TDD");
% This fixture changes an inherited FDD scenario to TDD. Keep the complete
% TDD common configuration coherent with the active 15 kHz carrier rather
% than retaining the 30 kHz reference numerology from the parent catalog.
activeSCS_kHz = double(sixgr.util.structGet(cfg, ...
    "phy.carrier.SubcarrierSpacing", ...
    sixgr.util.structGet(cfg, "frame.scs_khz", NaN)));
cfg = sixgr.util.structSet(cfg, ...
    "phy.duplex.tddCommon.ReferenceSubcarrierSpacingKHz", activeSCS_kHz);
cfg = sixgr.util.structSet(cfg, ...
    "phy.duplex.tddCommon.Pattern1.PeriodicityMilliseconds", 5.0);
cfg = sixgr.util.structSet(cfg, ...
    "phy.duplex.tddCommon.Pattern1.NumDownlinkSlots", 3);
cfg = sixgr.util.structSet(cfg, ...
    "phy.duplex.tddCommon.Pattern1.NumDownlinkSymbols", 12);
cfg = sixgr.util.structSet(cfg, ...
    "phy.duplex.tddCommon.Pattern1.NumUplinkSlots", 1);
cfg = sixgr.util.structSet(cfg, ...
    "phy.duplex.tddCommon.Pattern1.NumUplinkSymbols", 1);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.SymbolAllocation", [2 10]);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.MappingType", "A");
cfg = sixgr.util.structSet(cfg, "phy.pdsch.mappingType", "A");
cfg = sixgr.util.structSet(cfg, "phy.pdsch.enablePTRS", false);
carrierNRB = double(sixgr.util.structGet(cfg, "phy.carrier.NSizeGrid", NaN));
assert(isfinite(carrierNRB) && carrierNRB >= 1, ...
    "Control-gating fixture requires an explicit carrier grid size.");
cfg = sixgr.util.structSet(cfg, "phy.bwp.dl", ...
    struct("NStartBWP", 0, "NSizeBWP", carrierNRB));
cfg = sixgr.util.structSet(cfg, "phy.pdsch.PRBSet", 0:(carrierNRB - 1));
cfg = sixgr.util.structSet(cfg, "phy.pdcch.SymbolAllocation", [0 2]);
cfg = sixgr.util.structSet(cfg, "phy.pucch.SymbolAllocation", [12 2]);
cfg = sixgr.util.structSet(cfg, "phy.tddTiming.capabilityProfileID", ...
    "38.214-v18.8.0-cap1-dmrs-pos0-mu0");
cfg = sixgr.util.structSet(cfg, ...
    "phy.tddTiming.n1PDSCHProcessingTimeSymbols", 8);
cfg = sixgr.util.structSet(cfg, ...
    "phy.tddTiming.n2PUSCHPreparationTimeSymbols", 10);
cfg = sixgr.util.structSet(cfg, "referenceSignals.operationOrientation", "");
cfg = sixgr.util.structSet(cfg, "referenceSignals.csiAcquisitionMode", "");
cfg = sixgr.util.structSet(cfg, "lls6g.reference_signals.operation_orientation", "tdd_reciprocity");
cfg = sixgr.util.structSet(cfg, "lls6g.reference_signals.csi_acquisition_mode", "joint_dl_ul");
cfg = sixgr.util.structSet(cfg, "phy.waveform.sampleRate_Hz", 30.72e6);
cfg = sixgr.util.structSet(cfg, "run.controlGating.timingAdvanceUpdateMode", "measurement_only");
cfg = sixgr.util.structSet(cfg, "run.controlGating.timingAdvanceUpdateThresholdSamples", 0.25);
cfg = sixgr.util.structSet(cfg, "mac.scheduler.coverageOutageGuardEnabled", false);
cfg = sixgr.util.structSet(cfg, "system.scheduler.coverageOutageGuardEnabled", false);
if isfield(cfg.phy, "frameStructure")
    cfg.phy = rmfield(cfg.phy, "frameStructure");
end
if isfield(cfg, "resolved_runtime_view") && ...
        isfield(cfg.resolved_runtime_view, "frame_structure")
    cfg.resolved_runtime_view = rmfield(cfg.resolved_runtime_view, "frame_structure");
end
if isfield(cfg.phy, "frame")
    cfg.phy = rmfield(cfg.phy, "frame");
end
cfg = sixgr.phy.frame.FrameRuntimeStateBuilder.attachTimingContext(cfg);

multiUser = struct( ...
    "Enabled", true, ...
    "NumUsers", 1, ...
    "RNTIStart", 320, ...
    "ExecutionModel", "slot_coupled_truth");

state = sixgr.truth.CoupledTruthRuntime.initialize(cfg, fullfile(tmp, "run"), multiUser, struct(), 1);
state.CurrentServingIdx(:) = 1;
state.CurrentServingMetric_dBm(:) = -80;
state.DLQueueBits(:) = 1e8;
state.ULQueueBits(:) = 1e8;
state = sixgr.truth.CoupledTruthRuntime.startSlot(state, cfg, "DL", 1, 1, 1, 1, 10);
state = sixgr.truth.CoupledTruthRuntime.refreshControlState(state);

[stateBlocked, dlGrantsBlocked, ~] = sixgr.truth.CoupledTruthRuntime.scheduleDirection(state, cfg, "DL");
assert(isempty(dlGrantsBlocked), ...
    "PBCH/PRACH gating must block initial DL scheduling before acquisition/access succeed.");
assert(logical(stateBlocked.SchedulingEligibility(1)) == false, ...
    "SchedulingEligibility must stay false before PBCH/PRACH succeed.");

pbchPass = localControlTrial("PASS", double(state.CurrentSlot), double(state.CurrentFrame));
state = sixgr.truth.CoupledTruthRuntime.applyPBCHTrial(state, 1, pbchPass);
assert(string(state.CellAcquisitionState(1)) == "acquired", ...
    "PBCH pass must move the UE into acquired state.");

prachPass = localControlTrial("PASS", double(state.CurrentSlot), double(state.CurrentFrame));
prachPass.TimingAdvance_samples = 37;
prachPass.TimingAdvance_us = 1.204;
state = sixgr.truth.CoupledTruthRuntime.applyPRACHTrial(state, 1, prachPass);
assert(string(state.AccessState(1)) == "succeeded", ...
    "PRACH pass must move the UE into succeeded access state.");
assert(string(state.TimeAlignmentState(1)) == "time_aligned_from_prach" && ...
    double(state.LastTimingAdvanceSamplesByUE(1)) == 37 && ...
    abs(double(state.LastTimingAdvanceUsByUE(1)) - 1.204) < 1e-12, ...
    "PRACH timing advance must persist into the coupled UE time-alignment state.");
assert(string(state.LastTimingAdvanceSourceByUE(1)) == "prach_receiver_measurement" && ...
    isfinite(double(state.LastTimingAdvanceServingDistanceMByUE(1))), ...
    "PRACH timing advance must retain receiver-measurement source and serving-geometry baseline.");

simplePrach = localPRACHAnnotationRow("PASS");
annotatedSimple = sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("PRACH", simplePrach);
assert(strcmpi(string(annotatedSimple.SourceClassification(1)), "active_but_simplified") && ...
        contains(string(annotatedSimple.RuntimeMaterializationStatus(1)), "prach_detection_gate_no_full_ra_procedure"), ...
    "A PRACH detector row without Msg1-Msg4 RA evidence must not be promoted to full four-step RA materialization.");

incompleteFullPrach = simplePrach;
incompleteFullPrach.RAProcedureType(1) = "contention_based_four_step";
incompleteFullPrach.FullRAEvidenceSource(1) = "sixgr.phy.ra.runFourStepRA";
annotatedIncompleteFull = sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("PRACH", incompleteFullPrach);
assert(strcmpi(string(annotatedIncompleteFull.SourceClassification(1)), "active_but_simplified") && ...
        contains(string(annotatedIncompleteFull.RuntimeMaterializationStatus(1)), "prach_detection_gate_no_full_ra_procedure"), ...
    "A PRACH row with full-RA labels but no Msg1-Msg4 evidence must fail closed instead of claiming full four-step RA.");

fullPrachAttempt = simplePrach;
fullPrachAttempt.Status(1) = "FAIL";
fullPrachAttempt.CRCPass(1) = 0;
fullPrachAttempt.RAProcedureType(1) = "contention_based_four_step";
fullPrachAttempt.FullRAEvidenceSource(1) = "sixgr.phy.ra.runFourStepRA";
fullPrachAttempt.PreambleIndexTx(1) = 7;
fullPrachAttempt.RARNTI(1) = 1;
annotatedFull = sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("PRACH", fullPrachAttempt);
assert(strcmpi(string(annotatedFull.SourceClassification(1)), "active_integrated") && ...
        strcmpi(string(annotatedFull.RuntimeMaterializationStatus(1)), "active_integrated_four_step_ra_waveform_msg1_msg2_msg3_msg4"), ...
    "A failed full four-step RA attempt with real Msg1 evidence must retain full-RA provenance instead of being collapsed to simplified PRACH.");

[stateAfterAccessBlocked, dlGrantsBeforeSRS, ~] = sixgr.truth.CoupledTruthRuntime.scheduleDirection(state, cfg, "DL");
assert(isempty(dlGrantsBeforeSRS), ...
    "DL scheduling must stay blocked after PBCH/PRACH until configured SRS/CSI evidence is valid.");
assert(~logical(stateAfterAccessBlocked.SchedulingEligibility(1)), ...
    "DL scheduling eligibility must honor SRSRequired instead of bypassing it when CSI is enabled.");
assert(double(stateAfterAccessBlocked.SchedulingOpportunitiesBlockedByGatingCount(1)) >= 1, ...
    "Blocked pre-SRS DL traffic must increment the scheduling-gating opportunity counter.");
blockedArtifacts = sixgr.truth.CoupledTruthRuntime.mobilityArtifacts(stateAfterAccessBlocked);
blockedControlStateT = blockedArtifacts.ControlGatingStateTable;
assert(ismember("DLSchedulingEligibility", string(blockedControlStateT.Properties.VariableNames)) && ...
        ~logical(blockedControlStateT.DLSchedulingEligibility(1)), ...
    "Control-state export must report DL scheduling ineligible before valid SRS/CSI evidence.");

artifactsAfterPRACH = sixgr.truth.CoupledTruthRuntime.mobilityArtifacts(state);
controlStateT = artifactsAfterPRACH.ControlGatingStateTable;
assert(all(ismember(["TimeAlignmentState","LastTimingAdvance_samples","LastTimingAdvance_us", ...
        "LastTimingAdvanceSource","TimingAdvanceUpdateRequired","TimingAdvanceUpdateStatus"], string(controlStateT.Properties.VariableNames))) && ...
    strcmpi(string(controlStateT.TimeAlignmentState(1)), "time_aligned_from_prach") && ...
    double(controlStateT.LastTimingAdvance_samples(1)) == 37, ...
    "Control-state export must retain PRACH timing-advance evidence.");

stateMeasurementOnly = state;
stateMeasurementOnly.MobilityEnabled = false;
if size(stateMeasurementOnly.Layout.bs.pos_m, 1) > 1
    stateMeasurementOnly.Layout.bs.pos_m(2:end, :) = repmat(stateMeasurementOnly.Layout.bs.pos_m(1, :) + 1e6, ...
        size(stateMeasurementOnly.Layout.bs.pos_m, 1) - 1, 1);
end
stateMeasurementOnly.UE.pos_m(1, 3) = stateMeasurementOnly.UE.pos_m(1, 3) + 100;
stateMeasurementOnly = sixgr.truth.CoupledTruthRuntime.advanceFrame(stateMeasurementOnly, cfg, multiUser, 2, 10);
assert(logical(stateMeasurementOnly.TimingAdvanceUpdateRequiredByUE(1)) && ...
    string(stateMeasurementOnly.TimeAlignmentState(1)) == "ta_update_required_after_mobility" && ...
    string(stateMeasurementOnly.LastTimingAdvanceSourceByUE(1)) == "prach_receiver_measurement" && ...
    abs(double(stateMeasurementOnly.LastTimingAdvanceSamplesByUE(1)) - 37) < 1e-12, ...
    "Measurement-only TA mode must flag mobility drift without silently applying a geometry-derived TA command.");

ulTimingPass = localSRSTrial(double(stateMeasurementOnly.CurrentSlot), double(stateMeasurementOnly.CurrentFrame));
ulTimingPass.TimingOffset_samples = 41;
stateMeasurementOnly = sixgr.truth.CoupledTruthRuntime.applySRSTrial(stateMeasurementOnly, 1, ulTimingPass);
assert(string(stateMeasurementOnly.TimeAlignmentState(1)) == "time_aligned_from_srs_receiver_measurement" && ...
    string(stateMeasurementOnly.LastTimingAdvanceSourceByUE(1)) == "srs_receiver_timing_estimate" && ...
    abs(double(stateMeasurementOnly.LastTimingAdvanceSamplesByUE(1)) - 41) < 1e-12 && ...
    ~logical(stateMeasurementOnly.TimingAdvanceUpdateRequiredByUE(1)), ...
    "A real UL receiver timing estimate must refresh the UE timing-advance state and clear the mobility-drift update request.");

stateGeometryPredictive = stateMeasurementOnly;
stateGeometryPredictive.ControlGating.TimingAdvanceUpdateMode = "geometry_predictive";
stateGeometryPredictive.ControlGating.TimingAdvanceUpdateThresholdSamples = 0.25;
stateGeometryPredictive.UE.pos_m(1, 3) = stateGeometryPredictive.UE.pos_m(1, 3) + 100;
stateGeometryPredictive = sixgr.truth.CoupledTruthRuntime.advanceFrame(stateGeometryPredictive, cfg, multiUser, 3, 10);
assert(string(stateGeometryPredictive.TimeAlignmentState(1)) == "time_aligned_from_geometry_mobility_update" && ...
    string(stateGeometryPredictive.LastTimingAdvanceSourceByUE(1)) == "geometry_propagation_mobility_delta" && ...
    double(stateGeometryPredictive.LastTimingAdvanceSamplesByUE(1)) > 41 && ...
    string(stateGeometryPredictive.TimingAdvanceUpdateStatusByUE(1)) == "updated_from_geometry_mobility_delta", ...
    "Geometry-predictive TA mode must apply only a propagation-derived mobility delta with honest source labeling.");

syntheticSrsPass = localControlTrial("PASS", double(state.CurrentSlot), double(state.CurrentFrame));
stateSyntheticSrs = sixgr.truth.CoupledTruthRuntime.applySRSTrial(state, 1, syntheticSrsPass);
assert(string(stateSyntheticSrs.SRSValidityState(1)) == "invalid", ...
    "SRS gating must reject a generic PASS row without detection/channel-estimate evidence.");

srsPass = localSRSTrial(double(state.CurrentSlot), double(state.CurrentFrame));
srsPass.RIEstimate = 1;
srsPass.TPMIEstimate = 0;
srsPass.MeasuredTrialSINR_dB = 18;
srsPass.WidebandCQI = 10;
srsPass.CQIDerivedMCS = 11;
srsPass.CQIDerivedModulation = "64QAM";
srsPass.CQIDerivedTargetCodeRate = 0.455078125;
measuredSpatialSignature = complex([1 0; 0 1; 0 0; 0 0]);
srsPass.SpatialSignatureToken = string( ...
    sixgr.phy.mimo.MatrixContract.serialize(measuredSpatialSignature));
srsPass.SpatialSignatureSHA256 = string( ...
    sixgr.phy.mimo.MatrixContract.digest(measuredSpatialSignature));
srsPass.SpatialSignatureSource = ...
    "measured_srs_receiver_channel_estimate_dominant_rank_subspace";
state = sixgr.truth.CoupledTruthRuntime.applySRSTrial(state, 1, srsPass);
assert(string(state.SRSValidityState(1)) == "valid", ...
    "SRS pass must move the UE into valid SRS state.");
assert(logical(state.LatestULFeedback(1).Valid) && double(state.LatestULFeedback(1).RI) == 1, ...
    "SRS RI/TPMI evidence must feed the latest UL feedback state.");
assert(logical(state.LatestDLFeedback(1).Valid) && double(state.LatestDLFeedback(1).CQI) > 0 && ...
        isfinite(double(state.LatestDLFeedback(1).MCSIndex)), ...
    "TDD reciprocal SRS evidence from lls6g.reference_signals must feed measured DL AMC feedback.");
assert(string(state.LatestDLFeedback(1).SpatialSignatureToken) == srsPass.SpatialSignatureToken && ...
        string(state.LatestDLFeedback(1).SpatialSignatureSHA256) == srsPass.SpatialSignatureSHA256 && ...
        string(state.LatestDLFeedback(1).SpatialSignatureSource) == srsPass.SpatialSignatureSource && ...
        double(state.LatestDLFeedback(1).SpatialSignatureSourceSlot) == double(state.CurrentSlot) && ...
        string(state.LatestDLFeedback(1).SpatialSignatureMeasurementDirection) == "UL" && ...
        string(state.LatestDLFeedback(1).SpatialSignatureReciprocityMode) == "tdd_reciprocity", ...
    "TDD SRS reciprocity must preserve the exact measured spatial signature for DL MU scheduling.");
decodedDLSignature = sixgr.phy.mimo.MatrixContract.deserialize( ...
    state.LatestDLFeedback(1).SpatialSignatureToken, ...
    "ExpectedDigest", state.LatestDLFeedback(1).SpatialSignatureSHA256);
assert(isequal(decodedDLSignature, measuredSpatialSignature), ...
    "The reciprocal DL spatial signature must be the measured SRS matrix, not a reconstructed proxy.");

% A later data-derived CSI update has no new channel-subspace estimate and
% therefore must retain the prior measured SRS token and its original age.
dataFeedback = state.LatestDLFeedback(1);
dataFeedback.Direction = "DL";
dataFeedback.Slot = double(state.CurrentSlot) + 1;
dataFeedback.SpatialSignatureToken = "";
dataFeedback.SpatialSignatureSHA256 = "";
dataFeedback.SpatialSignatureSource = "";
dataFeedback.SpatialSignatureSourceSlot = NaN;
dataFeedback.SpatialSignatureMeasurementDirection = "";
dataFeedback.SpatialSignatureReciprocityMode = "";
preservedFeedback = sixgr.truth.CoupledTruthRuntime.preserveCausalMeasuredSRSSpatialSignatureRuntime( ...
    dataFeedback, state.LatestDLFeedback(1), cfg, "DL", double(state.CurrentSlot) + 1);
assert(string(preservedFeedback.SpatialSignatureToken) == srsPass.SpatialSignatureToken && ...
    string(preservedFeedback.SpatialSignatureSHA256) == srsPass.SpatialSignatureSHA256 && ...
    double(preservedFeedback.SpatialSignatureSourceSlot) == double(state.CurrentSlot), ...
    "Data CSI completion must not erase or retimestamp causal measured-SRS spatial authority.");

[stateReady, dlGrantsReady, ~] = sixgr.truth.CoupledTruthRuntime.scheduleDirection(state, cfg, "DL");
assert(~isempty(dlGrantsReady), ...
    "DL grants must appear once PBCH/PRACH gating is satisfied.");
grant = dlGrantsReady(1);
grantOperatingPointSource = lower(strtrim(string(sixgr.util.structGet( ...
    grant, "GrantOperatingPointSource", ""))));
assert(double(sixgr.util.structGet(grant, "MCSIndex", NaN)) > 1 && ...
        contains(grantOperatingPointSource, "srs_reciprocity") && ...
        contains(grantOperatingPointSource, "data_scheduler_input"), ...
    "DL grants after reciprocal SRS feedback must consume measured CQI-derived AMC before PHY execution. Observed MCS=%g source='%s' status='%s'.", ...
    double(sixgr.util.structGet(grant, "MCSIndex", NaN)), ...
    char(string(sixgr.util.structGet(grant, "GrantOperatingPointSource", ""))), ...
    char(string(sixgr.util.structGet(grant, "MCSValueStatus", ""))));
assert(strcmpi(char(string(sixgr.util.structGet(grant, "GrantControlState", ""))), "control_pending"), ...
    "Scheduled grants must start in the control_pending state when PDCCH gating is active.");

pdcchFail = localControlTrial("FAIL", double(grant.Slot), double(grant.Frame));
[stateReady, gatedGrant, allowExecution] = sixgr.truth.CoupledTruthRuntime.applyPDCCHGrantTrial(stateReady, grant, "DL", pdcchFail);
assert(~allowExecution, ...
    "Failed PDCCH gating must block PHY data execution for the scheduled grant.");
assert(strcmpi(char(string(sixgr.util.structGet(gatedGrant, "GrantControlState", ""))), "control_failed"), ...
    "Failed PDCCH gating must mark the grant as control_failed.");
assert(logical(stateReady.GrantsBlockedByGatingCount(1)) >= 1, ...
    "Failed PDCCH gating must increment the blocked-grant counter.");
assert(istable(stateReady.DLGrantTraceTable) && ~isempty(stateReady.DLGrantTraceTable) && ...
    strcmpi(char(string(stateReady.DLGrantTraceTable.GrantControlState(end))), "control_failed"), ...
    "Grant trace must record control_failed for blocked data grants.");

[stateReady, tddBlockedGrant] = sixgr.truth.CoupledTruthRuntime.blockPDCCHGrantTrial( ...
    stateReady, grant, "DL", "control_blocked_no_dl_control_symbols_in_tdd_slot");
assert(strcmpi(char(string(sixgr.util.structGet(tddBlockedGrant, "GrantControlState", ""))), ...
    "control_blocked_no_dl_control_symbols_in_tdd_slot"), ...
    "TDD slots with no DL control symbols must block PDCCH-gated grants explicitly.");
assert(~logical(sixgr.util.structGet(tddBlockedGrant, "ControlDecodeOk", true)), ...
    "TDD PDCCH slot-direction blocking must not mark control decode as successful.");

stateReady.CurrentSlot = double(stateReady.CurrentSlot) + double(stateReady.ControlGating.SRSMaxAgeSlots) + 1;
stateReady = sixgr.truth.CoupledTruthRuntime.refreshControlState(stateReady);
assert(string(stateReady.SRSValidityState(1)) == "stale", ...
    "SRS freshness gating must age successful SRS into stale state after the configured slot budget.");
assert(string(stateReady.CSIValidityState(1)) == "stale_srs_not_usable", ...
    "Stale SRS must switch CSI validity into an unavailable-for-fresh-CSI state.");

ok = true;
end

function T = localControlTrial(status, slotIdx, frameIdx)
row = table( ...
    string(status), double(slotIdx), double(frameIdx), ...
    'VariableNames', {'Status','Slot','Frame'});
if strcmpi(status, "PASS")
    row.CRCPass = 1;
else
    row.CRCPass = 0;
end
T = row;
end

function T = localSRSTrial(slotIdx, frameIdx)
T = localControlTrial("PASS", slotIdx, frameIdx);
T.DetectionAttempted = true;
T.DetectionSuccess = true;
T.DetectionUsable = true;
T.ResourceExtractionAttempted = true;
T.ResourceExtractionAvailable = true;
T.ChannelEstimateAttempted = true;
T.ChannelEstimateAvailable = true;
T.SRSChannelEstimateAvailable = true;
T.MeasurementAttempted = true;
T.MeasurementUsable = true;
T.StrictReceiverEvidenceOk = true;
T.StrictOk = true;
T.SRSRuntimeEvidenceUsable = true;
T.NMSE_dB = -20;
T.ReceiverHestSINR_dB = 18;
T.MeasuredTrialSINR_dB = 18;
T.FailureReason = "";
end

function T = localPRACHAnnotationRow(status)
T = table(string(status), 1, 1, 0, false, "", "", false, NaN, NaN, NaN, ...
    'VariableNames', {'Status','Slot','Frame','CRCPass','RACompleted','RAProcedureType', ...
    'FullRAEvidenceSource','PreambleDetected','PreambleIndexTx','RARNTI','TimingAdvanceCommand'});
end
