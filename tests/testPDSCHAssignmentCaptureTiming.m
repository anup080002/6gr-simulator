function ok=testPDSCHAssignmentCaptureTiming()
% Typed receive-path timing plumbing, not a decoded-DCI scheduler campaign.
setup6GRSimToolkit('Verbose',false);
outputRoot=tempname; mkdir(outputRoot);
fprintf('PDSCH_ASSIGNMENT_CAPTURE_OUTPUT=%s\n',outputRoot);
measurements=table();
fixture=StrictPDSCHChainFixture.create(2,'NPRB',6,'TransportBlockSize',384);
tx=sixgr.pdsch.PDSCHTransmitter(fixture.TransportBlocks,fixture.Assignment, ...
    fixture.ResourcePlan,fixture.Carrier,fixture.ReferenceConfig, ...
    'PrecoderBundle',fixture.PrecoderBundle);
receiver=fixture.ReceiverConfig;
receiver.ChannelModel='STATIC-MIMO';
receiver=rmfield(receiver,'ReferenceChannelGain');
cfg=struct('run',struct('pdschExecutionProfile','phy_calibration','strictMode',false));
cfg.phy.rx.cfoCorrectionEnabled=true;
cfg.phy.impairments.cfoEstimationMethod='cyclic_prefix';
% Conflicting initial configuration must not replace immutable allocation.
cfg.phy.pdsch.prbSet=0; cfg.phy.pdsch.dmrs.NSCID=1;
sampleRate=nrOFDMInfo(fixture.Carrier).SampleRate;
channel=[1 .15i; .1 .8*exp(.4i)];
% Independent receiver coding dimensions; no tx.CodingPlans input.
receivePlan=sixgr.pdsch.DLSCHCodingPlan.resolve( ...
    'TransportBlockSize',receiver.TransportBlockSizes, ...
    'TargetCodeRate',fixture.Assignment.get('TargetCodeRatePerCodeword'), ...
    'RV',fixture.Assignment.get('RVPerCodeword'), ...
    'Modulation',fixture.Assignment.get('ModulationPerCodeword'), ...
    'NumLayers',fixture.Assignment.get('LayerCountPerCodeword'), ...
    'RateMatchedBitCount',fixture.ResourcePlan.GPerCodeword);
args={'Assignment',fixture.Assignment,'ResourcePlan',fixture.ResourcePlan, ...
    'Carrier',fixture.Carrier,'ReferenceSignalConfig',fixture.ReferenceConfig, ...
    'ReceiverConfig',receiver,'ExecutionProfile','phy_calibration','CodingPlan',receivePlan};
for delay=[0 43]
    cfo=700*(1-2*(delay==0));
    upper=delay+20;
    physical=[complex(zeros(delay,2));tx.Waveform*channel;complex(zeros(upper-delay,2))];
    physical=physical.*exp(1i*2*pi*cfo*(0:size(physical,1)-1)'/sampleRate);
    received=.7*physical;
    [rx,info]=sixgr.phy.dl.PDSCH_Rx(received,cfg,args{:}, ...
        'TimingSearchWindowSamples',[0 upper], ...
        'PhysicalMeasurementWaveform',physical, ...
        'PhysicalMeasurementReferencePlane','receiver_antenna_connector_pre_composite_front_end', ...
        'PhysicalMeasurementSource','test_actual_connector_capture');
    assert(rx.CRCPass && isequal(rx.TransportBlock,vertcat(fixture.TransportBlocks{:})));
    assert(rx.ReceiveTiming.TimingOffsetSamples==delay && rx.TimingOffset==delay && ...
        rx.AppliedTimingCorrection_samples==delay && rx.TimingEstimateUsed && ...
        ~rx.ReceiveTiming.OracleTimingUsed && ~rx.ReceiveTiming.ReceiverZeroPaddingUsed);
    estimate=rx.ReceiverTrackingCorrection.EstimatedCFO_Hz;
    assert(abs(estimate-cfo)<15 && rx.ReceiverTrackingCorrection.CFOCorrectionApplied, ...
        'CFO must be estimated from the arriving CP samples, including sign.');
    assert(rx.ReceiveTiming.DemodulatedSampleCount==size(tx.Waveform,1) && ...
        rx.PhysicalMeasurementGridStatus=="available_exact_pre_front_end_grid");
    assert(norm(rx.PhysicalMeasurementGrid(:)-rx.OFDMGrid(:)/.7) ...
        <1e-10*norm(rx.PhysicalMeasurementGrid(:)), ...
        'Physical-plane and decode samples must use exactly the same measured alignment.');
    estimateTensor=rx.EffectiveLayerChannelEstimate;
    assert(info.CanonicalDelegation && ...
        isequal(size(estimateTensor),[12*fixture.Carrier.NSizeGrid 14 2 2]) && ...
        all(isfinite(estimateTensor(:))) && isempty(rx.ChannelGainPerPhysicalPort));
    assert(isequal(info.ReceiveTiming,rx.ReceiveTiming) && ...
        rx.EstimatedCFO_Hz==estimate && rx.CFOCorrectionApplied);
    save(fullfile(outputRoot,sprintf('capture_delay_%d.mat',delay)), ...
        'physical','received','rx','receiver','receivePlan','delay','cfo');
    row=table(delay,rx.TimingOffset,cfo,estimate, ...
        double(rx.ReceiveTiming.DemodulatedSampleCount),double(rx.CRCPass), ...
        nnz(rx.TransportBlock~=vertcat(fixture.TransportBlocks{:})), ...
        'VariableNames',{'InjectedDelaySamples','MeasuredDelaySamples', ...
        'InjectedCFO_Hz','MeasuredCFO_Hz','DemodulatedSampleCount','CRCPass','BitErrors'});
    measurements=[measurements;row]; %#ok<AGROW>
    sixgr.util.csvWriteTable(fullfile(outputRoot,'component_capture_timing.csv'),measurements);
    fprintf('PDSCH_ASSIGNMENT_CAPTURE_TIMING_PASS delay=%d cfo=%.3f estimate=%.3f bits=%d\n', ...
        delay,cfo,estimate,numel(rx.TransportBlock));
end
localReject(@()sixgr.phy.dl.PDSCH_Rx(received(1:end-1,:),cfg,args{:}, ...
    'TimingSearchWindowSamples',[0 upper]),'sixgr:phy:sync:IncompleteULReferenceObservation');
localReject(@()sixgr.phy.dl.PDSCH_Rx(received,cfg,args{:}, ...
    'TimingSearchWindowSamples',[0 upper],'SkipTimingEstimate',true), ...
    'sixgr:phy:dl:SharedPDSCHTimingBypassForbidden');
localReject(@()sixgr.phy.dl.PDSCH_Rx(received,cfg,args{:}, ...
    'TimingSearchWindowSamples',[0 upper],'FastAWGNPath',true), ...
    'sixgr:phy:dl:SharedPDSCHTimingBypassForbidden');
badPhysical=physical; badPhysical(1)=NaN;
localReject(@()sixgr.phy.dl.PDSCH_Rx(received,cfg,args{:}, ...
    'TimingSearchWindowSamples',[0 upper],'PhysicalMeasurementWaveform',badPhysical), ...
    'sixgr:phy:dl:InvalidAssignmentPhysicalMeasurement');
badCarrier=fixture.Carrier; badCarrier.NSlot=1;
badArgs=args; badArgs{6}=badCarrier;
localReject(@()sixgr.phy.dl.PDSCH_Rx(received,cfg,badArgs{:}, ...
    'TimingSearchWindowSamples',[0 upper]),'sixgr:phy:dl:AssignmentReceiveClockMismatch');
customData=fixture.ReferenceConfig.toStruct();
customData.OFDMOptions={'Nfft',2*nrOFDMInfo(fixture.Carrier).Nfft};
badArgs=args; badArgs{8}=sixgr.pdsch.PDSCHReferenceSignalConfig(customData);
localReject(@()sixgr.phy.dl.PDSCH_Rx(received,cfg,badArgs{:}, ...
    'TimingSearchWindowSamples',[0 upper]),'sixgr:phy:dl:AssignmentReceiveSampleClockUnsupported');
customData.OFDMOptions={'CarrierFrequency',1e6+111};
badArgs{8}=sixgr.pdsch.PDSCHReferenceSignalConfig(customData);
localReject(@()sixgr.phy.dl.PDSCH_Rx(received,cfg,badArgs{:}, ...
    'TimingSearchWindowSamples',[0 upper]),'sixgr:phy:dl:AssignmentReceiveSampleClockUnsupported');
fprintf('PDSCH_ASSIGNMENT_CAPTURE_NEGATIVES_PASS\n');
localCDLCapture(fixture,tx,cfg,args,receiver,sampleRate,outputRoot);
ok=true;
end

function localCDLCapture(fixture,tx,cfg,args,receiver,sampleRate,outputRoot)
% Exercise the new bounded capture branch on real, time-varying CDL-C.
fading=nrCDLChannel;
fading.DelayProfile='CDL-C'; fading.DelaySpread=100e-9;
fading.MaximumDopplerShift=30; fading.SampleRate=sampleRate;
fading.TransmitAntennaArray.Size=[1 2 1 1 1];
fading.ReceiveAntennaArray.Size=[1 2 1 1 1];
fading.Seed=90215;
delay=43; cfo=700;
% Silence is transmitted through the channel, not synthesized at the RX.
input=[complex(zeros(delay,2));tx.Waveform;complex(zeros(160-delay,2))];
physical=fading(input);
physical=physical.*exp(1i*2*pi*cfo*(0:size(physical,1)-1)'/sampleRate);
receiver.ChannelModel='CDL-C'; args{10}=receiver;
received=.7*physical;
[rx,~]=sixgr.phy.dl.PDSCH_Rx(received,cfg,args{:}, ...
    'TimingSearchWindowSamples',[0 120],'PhysicalMeasurementWaveform',physical, ...
    'PhysicalMeasurementReferencePlane','receiver_antenna_connector_pre_composite_front_end', ...
    'PhysicalMeasurementSource','test_actual_cdl_connector_capture');
assert(rx.CRCPass && isequal(rx.TransportBlock,vertcat(fixture.TransportBlocks{:})) && ...
    rx.TimingOffset>=delay && rx.TimingOffset<=120 && ...
    ~rx.ReceiveTiming.OracleTimingUsed && ~rx.ReceiveTiming.ReceiverZeroPaddingUsed);
assert(isequal(size(rx.EffectiveLayerChannelEstimate),[72 14 2 2]) && ...
    all(isfinite(rx.EffectiveLayerChannelEstimate(:))) && isempty(rx.ChannelGainPerPhysicalPort));
assert(norm(rx.PhysicalMeasurementGrid(:)-rx.OFDMGrid(:)/.7) ...
    <1e-10*norm(rx.PhysicalMeasurementGrid(:)));
save(fullfile(outputRoot,'capture_cdl_c.mat'),'physical','received','rx','receiver','delay','cfo');
measured=table(rx.TimingOffset,rx.EstimatedCFO_Hz, ...
    double(rx.CRCPass),nnz(rx.TransportBlock~=vertcat(fixture.TransportBlocks{:})), ...
    'VariableNames',{'MeasuredDelaySamples','MeasuredCFO_Hz','CRCPass','BitErrors'});
sixgr.util.csvWriteTable(fullfile(outputRoot,'component_cdl_capture_timing.csv'),measured);
fprintf('PDSCH_ASSIGNMENT_CDL_CAPTURE_PASS delay=%.3f cfo_estimate=%.3f bits=%d\n', ...
    rx.TimingOffset,rx.EstimatedCFO_Hz,numel(rx.TransportBlock));
end

function localReject(fn,id)
try, fn(); catch ME
    assert(strcmp(ME.identifier,id),'Expected %s, got %s: %s',id,ME.identifier,ME.message); return;
end
error('test:MissingRejection','Expected %s.',id);
end
