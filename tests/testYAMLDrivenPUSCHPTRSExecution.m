function ok = testYAMLDrivenPUSCHPTRSExecution()
%TESTYAMLDRIVENPUSCHPTRSEXECUTION Prove YAML controls real PUSCH PT-RS.

setup6GRSimToolkit("Verbose", false);
scenarioRoot = fullfile(pwd, "simulator", "configs", "scenarios");

enabledScenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    scenarioRoot, "webgui_sinr_sweep_64x4_mu_mimo_repair_slice.yaml"));
enabledCfg = sixgr.lls6g.buildInternalConfig(enabledScenario, tempdir);
assert(logical(enabledScenario.get("reference_signals.ptrs_enabled")) && ...
    enabledCfg.phy.pusch.enablePTRS, ...
    "The enabled YAML PT-RS flag must reach the production PUSCH config.");

% This is the exact first persisted Phase-19 UL allocation that originally
% exposed the rank-2 PT-RS port-projection defect.
grant = struct( ...
    "Direction", "UL", ...
    "Frame", 1, ...
    "Slot", 5, ...
    "RNTI", 1, ...
    "UEIndex", 1, ...
    "ServingCell", 1, ...
    "PRBSet", 0:11, ...
    "SymbolAllocation", [0 14], ...
    "Modulation", "QPSK", ...
    "NumLayers", 2, ...
    "Layers", 2, ...
    "TargetCodeRate", 0.1884765625, ...
    "MCSIndex", 1, ...
    "MCS", 1, ...
    "MCSTable", "qam256_table2", ...
    "TransmissionScheme", "codebook", ...
    "CodebookType", "codebook1_ng1n4n1", ...
    "NumLogicalPorts", 4, ...
    "TPMI", 0, ...
    "PMI", 0, ...
    "RI", 2, ...
    "SRSValid", true, ...
    "SRSCausalUsable", true, ...
    "SRSCausalMeasurementId", "phase19_srs_slot_4_ue_1", ...
    "LastSuccessfulSRSSlot", 4, ...
    "TBSBits", 1320, ...
    "XOverhead", 0, ...
    "TransformPrecoding", false, ...
    "GrantContextId", "phase19_yaml_ptrs_regression");
phyGrant = sixgr.phy.grant.freezePHYGrant( ...
    enabledCfg, "UL", grant, "SNR_dB", 20, "Frame", 1, "Slot", 5);
[enabledTx, enabledInfo] = sixgr.phy.ul.PUSCH_Tx( ...
    enabledCfg, "PHYGrant", phyGrant, "CompactOutput", true);
assert(phyGrant.CodingLayout.PTRSEnabled && ...
    isequal(phyGrant.CodingLayout.PTRSPortSet, 0) && ...
    enabledInfo.PTRS.Enabled && ...
    enabledInfo.PTRS.NativeSymbolCount > 0 && ...
    enabledInfo.PTRS.WaveformMappedRECount > 0 && ...
    isequal(enabledInfo.PTRS.LogicalPrecode.AssociatedDMRSPortSet, 0) && ...
    ismember(string(enabledInfo.PTRS.LogicalPrecode.Source), [ ...
        "scheduled_ptrs_dmrs_port_association_through_frozen_logical_precoder", ...
        "native_nrPUSCH_codebook_port_domain_with_scheduled_ptrs_dmrs_association"]) && ...
    size(enabledTx.Waveform, 2) == 4, ...
    ["YAML-enabled PT-RS must execute on its frozen DM-RS association and four UE elements. " + ...
     "grant=%d ports=%s native=%g mapped=%g assoc=%s source=%s waveformColumns=%d"], ...
    double(phyGrant.CodingLayout.PTRSEnabled), ...
    mat2str(double(phyGrant.CodingLayout.PTRSPortSet)), ...
    double(enabledInfo.PTRS.NativeSymbolCount), ...
    double(enabledInfo.PTRS.WaveformMappedRECount), ...
    mat2str(double(enabledInfo.PTRS.LogicalPrecode.AssociatedDMRSPortSet)), ...
    char(string(enabledInfo.PTRS.LogicalPrecode.Source)), size(enabledTx.Waveform, 2));
[enabledRx,~] = sixgr.phy.ul.PUSCH_Rx(enabledTx.Waveform,enabledCfg, ...
    "Carrier",enabledTx.Carrier,"PUSCH",enabledTx.PUSCH, ...
    "PUSCHIndices",enabledTx.PUSCHIndices, ...
    "TransportBlockSize",enabledTx.TransportBlockSize, ...
    "TargetCodeRate",enabledTx.TargetCodeRate,"RV",enabledTx.RV, ...
    "NoiseVar",1e-12,"NoiseVarDomain","grid", ...
    "CompactOutput",false,"SkipTimingEstimate",true);
assert(enabledRx.Ok && ~enabledRx.CRCError, ...
    "YAML-enabled rank-2 PUSCH PT-RS must survive an exact noiseless Tx/Rx roundtrip.");
contradictoryPUSCH = enabledTx.PUSCH;
contradictoryPUSCH.EnablePTRS = false;
localAssertThrows(@() sixgr.phy.ul.PUSCH_Tx( ...
    enabledCfg, "PUSCH", contradictoryPUSCH, "CompactOutput", true), ...
    "sixgr:config:YAMLFeatureExecutionMismatch");

disabledScenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    scenarioRoot, "master_sinr_sweep.yaml"));
disabledCfg = sixgr.lls6g.buildInternalConfig(disabledScenario, tempdir);
assert(~logical(disabledScenario.get("reference_signals.ptrs_enabled")) && ...
    ~disabledCfg.phy.pusch.enablePTRS, ...
    "The disabled YAML PT-RS flag must reach the production PUSCH config.");
[disabledTx, disabledInfo] = sixgr.phy.ul.PUSCH_Tx( ...
    disabledCfg, "CompactOutput", true); %#ok<ASGLU>
assert(~disabledInfo.PTRS.Enabled && ...
    disabledInfo.PTRS.NativeSymbolCount == 0 && ...
    disabledInfo.PTRS.WaveformMappedRECount == 0, ...
    "YAML-disabled PT-RS must produce no native or waveform PT-RS REs.");

ok = true;
end

function localAssertThrows(fcn, identifier)
didThrow = false;
try
    fcn();
catch ME
    didThrow = strcmp(string(ME.identifier), string(identifier));
    if ~didThrow
        rethrow(ME);
    end
end
assert(didThrow, "Expected typed error %s.", identifier);
end
