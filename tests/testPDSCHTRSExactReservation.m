function ok = testPDSCHTRSExactReservation()
%TESTPDSCHTRSEXACTRESERVATION TRS occasions puncture exact PDSCH data REs.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
root = fileparts(fileparts(mfilename("fullpath")));
scenarioPath = fullfile(root, "simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring_tdd.yaml");
scenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scenario, string(tempname));

% Isolate TRS ownership from the independent CSI-RS reservation in this
% focused test. The production scenario enables both and the allocator
% composes their exact ReservedRE sets.
cfg.phy.csirs.enable = false;

% Periodic TRS authority is defined in absolute zero-based slots.  Verify
% the YAML period/offset path independently of an explicit slot-number
% list so a valid periodic configuration cannot silently become active in
% every slot (or in no slot) after normalization.
cfgPeriodic = cfg;
if isfield(cfgPeriodic.phy.trs, "slotNumbers")
    cfgPeriodic.phy.trs = rmfield(cfgPeriodic.phy.trs, "slotNumbers");
end
if isfield(cfgPeriodic, "lls6g") && ...
        isfield(cfgPeriodic.lls6g, "reference_signals") && ...
        isfield(cfgPeriodic.lls6g.reference_signals, "trs") && ...
        isfield(cfgPeriodic.lls6g.reference_signals.trs, "slot_numbers")
    cfgPeriodic.lls6g.reference_signals.trs = rmfield( ...
        cfgPeriodic.lls6g.reference_signals.trs, "slot_numbers");
end
cfgPeriodic.phy.trs.period_slots = 5;
cfgPeriodic.phy.trs.period_offset = 2;
assert(~sixgr.truth.isActiveTRSOccasion(cfgPeriodic, 2) && ...
    sixgr.truth.isActiveTRSOccasion(cfgPeriodic, 3) && ...
    ~sixgr.truth.isActiveTRSOccasion(cfgPeriodic, 4) && ...
    sixgr.truth.isActiveTRSOccasion(cfgPeriodic, 8), ...
    ["TRS period/offset authority must activate absolute zero-based " ...
     "slots 2, 7, ... and no intervening slots."]);
periodicTRS = sixgr.phy.trs.buildTRSConfigFromScenario(cfgPeriodic, ...
    "RunId", "test_periodic_trs_authority", ...
    "ScenarioName", "test_periodic_trs_authority");
assert(string(periodicTRS.SlotAuthority) == "periodic_offset" && ...
    periodicTRS.PeriodSlots == 5 && periodicTRS.PeriodOffset == 2 && ...
    isequal(periodicTRS.SlotNumbers, 2), ...
    "The Toolbox TRS resource must preserve the exact YAML period and offset.");

cfg.phy.carrier.NSlot = 7;
carrier = sixgr.phy.grid.makeCarrier(cfg);
prbSet = 0:(double(carrier.NSizeGrid) - 1);
symAlloc = [2 12];

[dataInd, info, pdsch] = sixgr.phy.grid.allocREsPDSCH(carrier, cfg, ...
    "IndexBase", "0based", "PRBSet", prbSet, ...
    "SymbolAllocation", symAlloc, "NumLayers", 1, ...
    "Modulation", "QPSK", "MappingType", "A");
assert(~isempty(pdsch.ReservedRE), ...
    "An active TRS occasion must install exact PDSCH ReservedRE entries.");

strictTRS = sixgr.phy.trs.buildTRSConfigFromScenario(cfg, ...
    "RunId", "test_pdsch_trs_reservation", ...
    "ScenarioName", "test_pdsch_trs_reservation");
trsInd = nrCSIRSIndices(carrier, strictTRS.ToolboxCSIRS, ...
    "IndexStyle", "index", "IndexBase", "0based");
plane = double(carrier.NSizeGrid) * 12 * double(carrier.SymbolsPerSlot);
expected = unique(mod(double(trsInd(:)), plane), "sorted");
assert(all(ismember(expected, double(pdsch.ReservedRE(:)))), ...
    "Every active in-allocation TRS RE must be owned by PDSCH ReservedRE.");

dataBase = unique(mod(double(dataInd(:)), plane));
dmrsSub = nrPDSCHDMRSIndices(carrier, pdsch, ...
    "IndexStyle", "subscript", "IndexBase", "0based");
dmrsBase = unique(double(dmrsSub(:,1) + ...
    12 * double(carrier.NSizeGrid) * dmrsSub(:,2)));
assert(isempty(intersect(expected, dataBase)) && ...
    isempty(intersect(expected, dmrsBase)), ...
    "TRS must be disjoint from transmitted PDSCH data and DM-RS REs.");
if logical(pdsch.EnablePTRS)
    ptrsInd = nrPDSCHPTRSIndices(carrier, pdsch, ...
        "IndexStyle", "index", "IndexBase", "0based");
    ptrsBase = unique(mod(double(ptrsInd(:)), plane));
    assert(isempty(intersect(expected, ptrsBase)), ...
        "TRS must be disjoint from transmitted PDSCH PT-RS REs.");
end
assert(double(info.NRE) > 0, ...
    "TRS puncturing must retain a nonempty PDSCH data allocation.");

% A non-TRS slot must retain the extra data REs. This also guards the
% scheduler's slot-scoped exact-NRE/TBS cache against cross-slot reuse.
cfgNonTRS = cfg;
cfgNonTRS.phy.carrier.NSlot = 6;
carrierNonTRS = sixgr.phy.grid.makeCarrier(cfgNonTRS);
[~, infoNonTRS, pdschNonTRS] = sixgr.phy.grid.allocREsPDSCH( ...
    carrierNonTRS, cfgNonTRS, "IndexBase", "0based", ...
    "PRBSet", prbSet, "SymbolAllocation", symAlloc, ...
    "NumLayers", 1, "Modulation", "QPSK", "MappingType", "A");
assert(isempty(pdschNonTRS.ReservedRE), ...
    "A non-TRS slot must not inherit a prior slot's TRS reservation.");
assert(double(infoNonTRS.NRE) > double(info.NRE), ...
    "Active TRS ownership must reduce the exact PDSCH data-RE budget.");
assert(double(info.G) < double(infoNonTRS.G), ...
    "Active TRS ownership must reduce the exact coded-bit budget G used by rate matching.");
assert(double(info.NREPerPRB) == double(infoNonTRS.NREPerPRB), ...
    ["TRS puncturing must not be misrepresented as a different 38.214 " ...
     "NREPerPRB/TBS input; its effect belongs in exact rate-matching G."]);

% A YAML schedule that places TRS over PDSCH DM-RS is invalid and must fail
% before coding or mapping; silently puncturing DM-RS would corrupt channel
% estimation and conceal the configuration defect.
colliding = cfg;
colliding.phy.trs.symbolLocation = 2;
try
    sixgr.phy.grid.allocREsPDSCH(carrier, colliding, ...
        "IndexBase", "0based", "PRBSet", prbSet, ...
        "SymbolAllocation", symAlloc, "NumLayers", 1, ...
        "Modulation", "QPSK", "MappingType", "A");
    error("testPDSCHTRSExactReservation:MissingCollisionGuard", ...
        "A TRS/PDSCH-DM-RS collision must fail closed.");
catch ME
    assert(strcmp(ME.identifier, ...
        "sixgr:phy:grid:allocREsPDSCH:TRSDMRSCollision"), ...
        "Unexpected TRS/DM-RS collision failure: %s", ME.identifier);
end

ok = true;
end
