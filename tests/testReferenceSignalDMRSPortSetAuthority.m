function ok = testReferenceSignalDMRSPortSetAuthority()
%TESTREFERENCESIGNALDMRSPORTSETAUTHORITY Preserve YAML DM-RS port pools.

setup6GRSimToolkit("Verbose", false);
scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "variants", "SCN00_BOUNDED_WAVEFORM_TRUTH_SCALE.yaml");
scenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scenario, ...
    fullfile(tempdir, "sixgr_dmrs_port_authority"));

expectedPorts = [0 1];
assert(double(cfg.phy.pdsch.dmrs.nPorts) == 2 && ...
    isequal(double(cfg.phy.pdsch.dmrs.portSet(:).'), expectedPorts), ...
    "PDSCH YAML DM-RS port_set must survive config translation exactly.");
assert(double(cfg.phy.pusch.dmrs.nPorts) == 2 && ...
    isequal(double(cfg.phy.pusch.dmrs.portSet(:).'), expectedPorts), ...
    "PUSCH YAML DM-RS port_set must survive config translation exactly.");

[ulPorts, ulSource] = sixgr.phy.grant.resolveScheduledDMRSPortSet( ...
    cfg, "UL", 2, struct());
assert(isequal(double(ulPorts(:).'), expectedPorts) && ...
    string(ulSource) == "configured_active_dmrs_port_pool", ...
    "A rank-two UL grant must consume both configured logical DM-RS ports.");

carrier = sixgr.phy.grid.makeCarrier(cfg);
[indices, info, pusch] = sixgr.phy.grid.allocREsPUSCH( ...
    carrier, cfg, "PRBSet", 0:11, "SymbolAllocation", [0 14], ...
    "Modulation", "16QAM", "NumLayers", 2);
assert(~isempty(indices) && info.NRE > 0 && info.DMRSRE > 0, ...
    "The YAML-derived rank-two PUSCH allocation must materialize data and DM-RS REs.");
assert(isequal(double(pusch.DMRS.DMRSPortSet(:).'), expectedPorts), ...
    "The emitted nrPUSCHConfig must retain the scheduled two-port DM-RS set.");

% A multi-user scheduler may expose a wider pool while freezing a distinct
% active subset for each grant. Exact replay must consume the frozen subset
% without shrinking or mutating the scheduler's scenario-wide pool.
grantCfg = localFourPortGrantConfig();
phyGrantUL = localFreezeGrant(grantCfg, "UL", [2 3]);
replayUL = sixgr.phy.grant.applyPHYGrantToConfig(grantCfg, phyGrantUL);
[ulReplayPorts, ulReplaySource] = sixgr.phy.grant.resolveScheduledDMRSPortSet( ...
    replayUL, "UL", 2, struct());
assert(isequal(double(ulReplayPorts(:).'), [2 3]) && ...
    string(ulReplaySource) == "frozen_phy_grant_dmrs_port_set", ...
    "UL exact replay must prefer frozen DM-RS ports over the scheduler pool.");
assert(isequal(double(replayUL.phy.pusch.dmrs.availablePortSet(:).'), [0 1 2 3]), ...
    "UL exact replay must not shrink the scenario-wide scheduler port pool.");

phyGrantDL = localFreezeGrant(grantCfg, "DL", [2 3]);
replayDL = sixgr.phy.grant.applyPHYGrantToConfig(grantCfg, phyGrantDL);
[dlReplayPorts, dlReplaySource] = sixgr.phy.grant.resolveScheduledDMRSPortSet( ...
    replayDL, "DL", 2, struct());
assert(isequal(double(dlReplayPorts(:).'), [2 3]) && ...
    string(dlReplaySource) == "frozen_phy_grant_dmrs_port_set", ...
    "DL exact replay must prefer frozen DM-RS ports over the scheduler pool.");
assert(isequal(double(replayDL.phy.pdsch.dmrs.availablePortSet(:).'), [0 1 2 3]), ...
    "DL exact replay must not shrink the scenario-wide scheduler port pool.");

ok = true;
end

function cfg = localFourPortGrantConfig()
cfg = sixgr.config.defaultConfig();
cfg.run.strictMode = true;
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.nTxAnt = 4;
cfg.channel.nRxAnt = 4;
cfg.phy.nTxAnt = 4;
cfg.phy.nRxAnt = 4;
cfg.phy.carrier.NSizeGrid = 24;
cfg.antenna.bs.numElements = 4;
cfg.antenna.bs.numRFChains = 4;
cfg.antenna.ue.numElements = 4;
cfg.antenna.ue.numRFChains = 4;
cfg.rf.bs.numRFChains = 4;
cfg.rf.ue.numRFChains = 4;
for root = ["phy.pdsch", "phy.pusch"]
    cfg = sixgr.util.structSet(cfg, root + ".prbSet", 0:11);
    cfg = sixgr.util.structSet(cfg, root + ".symbolAllocation", [0 14]);
    cfg = sixgr.util.structSet(cfg, root + ".modulation", "QPSK");
    cfg = sixgr.util.structSet(cfg, root + ".codeRate", 0.3);
    cfg = sixgr.util.structSet(cfg, root + ".numLayers", 2);
    cfg = sixgr.util.structSet(cfg, root + ".nLayers", 2);
    cfg = sixgr.util.structSet(cfg, root + ".numPorts", 4);
    cfg = sixgr.util.structSet(cfg, root + ".nPorts", 4);
    cfg = sixgr.util.structSet(cfg, root + ".enablePTRS", false);
    cfg = sixgr.util.structSet(cfg, root + ".dmrs.availablePortSet", [0 1 2 3]);
    cfg = sixgr.util.structSet(cfg, root + ".dmrs.portSet", [0 1 2 3]);
end
cfg.phy.pusch.NumAntennaPorts = 4;
cfg.phy.pusch.numAntennaPorts = 4;
cfg.phy.pusch.transmissionScheme = "nonCodebook";
cfg.phy.pusch.transformPrecoding = false;
cfg.phy.pdsch.precoding.normalizationConvention = "semi_unitary";
cfg.phy.pusch.precoding.normalizationConvention = "semi_unitary";
end

function phyGrant = localFreezeGrant(cfg, direction, dmrsPorts)
numLayers = numel(dmrsPorts);
logicalW = eye(4, numLayers);
grant = struct( ...
    "Direction", char(direction), ...
    "Frame", 0, ...
    "Slot", 0, ...
    "UEIndex", 1, ...
    "RNTI", 71 + double(upper(string(direction)) == "UL"), ...
    "ServingCell", 1, ...
    "PRBSet", 0:11, ...
    "SymbolAllocation", [0 14], ...
    "Modulation", "QPSK", ...
    "MCSIndex", 4, ...
    "TargetCodeRate", 0.3, ...
    "NumLayers", numLayers, ...
    "NumLogicalPorts", 4, ...
    "DMRSPortSet", dmrsPorts, ...
    "PrecodingMatrix", logicalW, ...
    "PrecodingMatrixLogicalPorts", logicalW, ...
    "PrecodingActive", true, ...
    "GrantContextId", sprintf('%s|dmrs=%s', char(direction), mat2str(dmrsPorts)), ...
    "HARQ", struct("HarqID", 0, "NDI", true, "RV", 0, "IsRetransmission", false));
if upper(string(direction)) == "UL"
    grant.TransmissionScheme = "nonCodebook";
    grant.TransformPrecoding = false;
end
phyGrant = sixgr.phy.grant.freezePHYGrant( ...
    cfg, direction, grant, "Frame", 0, "Slot", 0, "SNR_dB", 30);
assert(logical(phyGrant.IsFrozen), ...
    "The regression must exercise a production-frozen PHYGrant.");
end
