function ok=testPUCCHReceiverStageEvidence()
% Metadata-only stage export guard; no physical detector qualification.
setup6GRSimToolkit('Verbose',false,'RunToolboxChecks',false);
rx=struct('ChannelEstimationMode',"dmrs_per_resource_mmse_equalization", ...
    'ChannelEstimate',ones(12,14),'EqualizerInfo',struct('Method',"MMSE"), ...
    'ReceiveTiming',struct('TimingOffsetSamples',0,'AppliedTimingCorrectionSamples',0, ...
        'TimingSource',"received_reference_correlation_bounded_search", ...
        'OracleTimingUsed',false,'ReceiverZeroPaddingUsed',false, ...
        'InputSampleCount',7834,'DemodulatedSampleCount',7680), ...
    'EffectiveGridNoiseInterferenceVariance',0.25, ...
    'DecodeNoiseInterferenceVariance',0.07, ...
    'EqualizedDecodeNoiseInterferenceVariance',0.07, ...
    'NoncoherentSequenceDetection',false);
original=rx;
actual=sixgr.link.pucchReceiverStageEvidence(rx);
assert(actual.ChannelEstimateAttempted && actual.EqualizationAttempted && ...
    actual.ChannelEstimateAvailable && actual.EqualizationAvailable && ...
    ~contains(actual.ChannelEstimateSource,'unit_channel'));
assert(actual.TimingEstimateUsed && actual.EstimatedTimingOffsetSamples==0 && ...
    actual.ReceiverDemodulatedSampleCount==7680 && actual.ReceiverInputSampleCount==7834);
assert(actual.EffectiveGridNoiseInterferenceVariance==0.25 && ...
    actual.DecodeNoiseInterferenceVariance==0.07 && ...
    actual.EqualizedDecodeNoiseInterferenceVariance==0.07 && ...
    actual.DecodeNoiseVarianceDomain=="equalized_symbol");
assert(isequaln(rx,original),'Stage publication must not change receiver evidence.');
assert(~isfield(actual,'SuccessFlag') && ~isfield(actual,'CRCPass') && ...
    ~isfield(actual,'UCIExpectedBitVector'),'Do not invent a transmitted reference or pass.');
% SR acquisition selects and applies a received-sequence timing candidate;
% reporting that application does not assert detection or timing lock.
rx.ReceiveTiming.TimingSource="received_configured_SR_sequence_bounded_search";
rx.ReceiveTiming.TimingOffsetSamples=83;
rx.ReceiveTiming.AppliedTimingCorrectionSamples=83;
sr=sixgr.link.pucchReceiverStageEvidence(rx);
assert(sr.TimingEstimateUsed && sr.AppliedTimingCorrectionSamples==83, ...
    'test:SRReceivedTimingApplicationNotExported', ...
    'Actual applied SR reference acquisition must retain its timing-application flag.');
rx.ReceiveTiming.OracleTimingUsed=true;
assert(~sixgr.link.pucchReceiverStageEvidence(rx).TimingEstimateUsed, ...
    'Injected timing must never count as a received estimate.');
rx=original;
rx.ReceiveTiming.TimingOffsetSamples=NaN;
rx.ReceiveTiming.AppliedTimingCorrectionSamples=77;
rx.ReceiveTiming.TimingSource="prior_received_UL_pilot_constant_phase_prediction";
prior=sixgr.link.pucchReceiverStageEvidence(rx);
assert(~prior.TimingEstimateUsed && isnan(prior.EstimatedTimingOffsetSamples) && ...
    prior.AppliedTimingCorrectionSamples==77,'Prior timing is not a new measurement.');
rx.ChannelEstimate=[]; rx.EqualizerInfo=struct();
incomplete=sixgr.link.pucchReceiverStageEvidence(rx);
assert(incomplete.ChannelEstimateAttempted && ~incomplete.ChannelEstimateAvailable && ...
    incomplete.EqualizationAttempted && ~incomplete.EqualizationAvailable);
for mode=["awgn_direct_resource_extraction","format0_noncoherent_sequence_detection"]
    rx.ChannelEstimationMode=mode; rx.NoncoherentSequenceDetection=true;
    rx.DecodeNoiseInterferenceVariance=NaN;
    rx.EqualizedDecodeNoiseInterferenceVariance=NaN;
    direct=sixgr.link.pucchReceiverStageEvidence(rx);
    assert(~direct.ChannelEstimateAttempted && ~direct.EqualizationAttempted && ...
        startsWith(direct.ChannelEstimateSource,'not_applicable_') && ...
        isnan(direct.DecodeNoiseInterferenceVariance) && ...
        direct.DecodeNoiseVarianceDomain=="not_consumed_noncoherent_sequence_detection");
end
% Legacy standalone Format-0 trials can explicitly provide grid variance.
% The absence of DM-RS alone does not prove that variance was not consumed.
rx.DecodeNoiseInterferenceVariance=0.25;
rx.EqualizedDecodeNoiseInterferenceVariance=0.25;
provided=sixgr.link.pucchReceiverStageEvidence(rx);
assert(provided.DecodeNoiseInterferenceVariance==0.25 && ...
    provided.DecodeNoiseVarianceDomain=="resource_grid_direct_extraction");
fprintf('PUCCH_RECEIVER_STAGE_EVIDENCE_PASS metadata_only=1\n');
ok=true;
end
