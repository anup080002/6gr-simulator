function ok=testAbsoluteReferenceNoisePublication()
% Explicit receipt fixtures test metadata integrity, NOT waveform accuracy.
defaults=sixgr.link.absoluteReferenceNoisePublication();
assert(~defaults.AbsoluteReferenceNoiseEvidenceAvailable&& ...
    isnan(defaults.ReferenceNoiseSampleVariance_mW)&& ...
    strlength(defaults.AbsoluteReferenceNoiseJSON)==0);
assert(isequaln(defaults,sixgr.link.absoluteReferenceNoisePublication(struct())));
checks=0;
for direction=["DL","UL"]
    for target=[-20,-10,0,20,30]
        replay=fixture(direction,target); original=replay;
        fields=sixgr.link.absoluteReferenceNoisePublication(replay);
        assert(isequaln(replay,original),'Publisher modified original evidence.');
        assert(fields.AbsoluteReferenceNoiseEvidenceAvailable&& ...
            fields.RequestedReferenceEsN0_dB==target&& ...
            fields.ThermalNoiseApplied==0&&fields.ControlledReferenceNoiseApplied==1);
        assert(fields.ReferenceNoiseSampleVariance_mW== ...
            replay.AbsoluteReferenceNoise.NoisePSD_mWPerHz*replay.SampleRate_Hz);
        assert(fields.AbsoluteReferenceNoiseInjectedSampleVariance_mW== ...
            replay.AbsoluteReferenceNoiseInjectedSampleVariance_mW);
        assert(fields.AbsoluteReferenceNoiseJSON==string(jsonencode(replay.AbsoluteReferenceNoise)));
        assert(fields.AbsoluteReferenceNoiseJSONSHA256== ...
            string(sixgr.util.sha256Hex(char(fields.AbsoluteReferenceNoiseJSON))));
        % Retain noise generation independently of post-RF effective noise.
        replay.InjectedNoiseVariance=7*replay.ReferenceNoiseSampleVariance_mW;
        replay.InjectedNoiseVariancePreCompositeFrontEnd=3*replay.ReferenceNoiseSampleVariance_mW;
        assert(isequaln(fields,sixgr.link.absoluteReferenceNoisePublication(replay)));
        checks=checks+1;
    end
end
replay=fixture("DL",0);
broken=replay; broken=rmfield(broken,'AbsoluteReferenceNoiseInjectedSampleVariance_mW'); rejects(broken);
broken=replay; broken.AbsoluteReferenceNoiseInjectedSampleVariance_mW=NaN; rejects(broken);
broken=replay; broken.AbsoluteReferenceNoiseInjectedSampleVariance_mW=2*broken.ReferenceNoiseSampleVariance_mW; rejects(broken);
broken=replay; broken.AbsoluteReferenceNoiseInjectionDomain="post_equalizer"; rejects(broken);
broken=replay; broken.ReferenceNoisePSD_mWPerHz=2*broken.ReferenceNoisePSD_mWPerHz; rejects(broken);
broken=replay; broken.SampleRate_Hz=broken.SampleRate_Hz/2; rejects(broken);
broken=replay; broken.PowerContextDirection="UL"; rejects(broken);
broken=replay; broken.PowerContextAmplitudeUnit="normalized"; rejects(broken);
broken=replay; broken.ThermalNoiseApplied=true; rejects(broken);
broken=replay; broken.ThermalNoiseApplied=0; rejects(broken);
broken=replay; broken.ControlledReferenceNoiseApplied=1; rejects(broken);
broken=replay; broken.RequestedReferenceEsN0_dB=int32(0); rejects(broken);
broken=replay; broken.NoiseOperatingMode="receiver_noise_figure_thermal_noise"; rejects(broken);
broken=replay; broken=rmfield(broken,'ReferenceNoiseSource'); rejects(broken);
broken=replay; broken.AbsoluteReferenceNoise.ReferenceIsMeasured=true; rejects(broken);
% Pre-draw resolver must work before any original draw is made, but that
% planned receipt must NOT become published execution evidence.
planned=rmfield(replay,{'AbsoluteReferenceNoiseInjectedSampleVariance_mW', ...
    'AbsoluteReferenceNoiseInjectionDomain'});
variance=sixgr.link.resolveAbsoluteReferenceNoiseVariance(planned);
assert(variance==replay.ReferenceNoiseSampleVariance_mW); rejects(planned);
rows=sixgr.truth.emptyCSIRSTrialTable();
assert(all(ismember(fieldnames(defaults),rows.Properties.VariableNames)));
fprintf('ABSOLUTE_REFERENCE_PUBLICATION_PASS receipts=%d negative_cases=16 waveform_qualification=0\n',checks);
ok=true;
end

function rejects(replay)
try
    sixgr.link.absoluteReferenceNoisePublication(replay);
catch failure
    assert(startsWith(string(failure.identifier),"sixgr:link:AbsoluteReferenceNoise"), ...
        'Unexpected rejection: %s',failure.identifier);
    return;
end
error('test:AbsoluteReferenceAcceptedCorruption','Corrupt or incomplete original evidence was accepted.');
end

function replay=fixture(direction,target)
power=30; if direction=="UL", power=23; end
loss=96.988098; k=612; scs=30e3; fs=30.72e6;
epre=10^((power-loss-10*log10(k))/10);
psd=10^((10*log10(epre)-target-10*log10(scs))/10);
receipt=struct('NoiseOperatingMode',"absolute_reference_esn0", ...
    'WaveformAmplitudeUnit',"sqrt_mW",'Direction',direction, ...
    'RequestedReferenceEsN0_dB',target,'ReferenceEPRE_mW',epre, ...
    'ReferenceSubcarrierSpacing_Hz',scs,'ReferenceBWPSubcarrierCount',k, ...
    'NominalTxTotalPower_dBm',power,'ReferencePathloss_dB',loss, ...
    'NoisePSD_mWPerHz',psd,'SampleRate_Hz',fs,'SampleNoiseVariance_mW',psd*fs, ...
    'Source',"declared_nominal_full_bwp_unity_array_nrPathLoss_reference_not_measured", ...
    'ReferenceContractVersion',"sixgr.link.absolute_reference_noise/v1", ...
    'ReferenceContractSHA256',string(repmat('a',1,64)), ...
    'ReferenceModel',"nominal_full_bwp_unity_array", ...
    'ReferencePoint',"declared_pre_fading_unity_array_receive_reference_before_RX_front_end", ...
    'ReferenceIsMeasured',false,'ThermalNoiseApplied',false,'NoiseFigureApplied',false, ...
    'ReferencePathlossEvaluatedThisCall',false,'Classification',"IMPLEMENTATION_POLICY", ...
    'ResearchClass',"optional_research_experiment");
replay=struct('NoiseOperatingMode',receipt.NoiseOperatingMode, ...
    'AbsoluteReferenceNoise',receipt,'SampleRate_Hz',fs, ...
    'PowerContextAmplitudeUnit',"sqrt_mW",'PowerContextDirection',direction, ...
    'RequestedReferenceEsN0_dB',target,'ReferenceNoisePSD_mWPerHz',psd, ...
    'ReferenceNoiseSampleVariance_mW',psd*fs,'ReferenceNoiseSampleRate_Hz',fs, ...
    'ReferenceNoiseContractSHA256',receipt.ReferenceContractSHA256, ...
    'ReferenceNoiseSource',receipt.Source,'ReferenceNoiseReferencePlane',receipt.ReferencePoint, ...
    'ThermalNoiseApplied',false,'ControlledReferenceNoiseApplied',true, ...
    'AbsoluteReferenceNoiseInjectedSampleVariance_mW',psd*fs, ...
    'AbsoluteReferenceNoiseInjectionDomain',"receiver_sample_waveform_pre_composite_front_end");
end
