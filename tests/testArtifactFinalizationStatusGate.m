function localRemove(pathValue)
if isfolder(pathValue)
    rmdir(pathValue, "s");
end
end

function value = localLogical(raw)
if islogical(raw)
    value = raw;
elseif isnumeric(raw)
    value = raw ~= 0;
else
    value = ismember(lower(strtrim(string(raw))), ["true", "1", "yes", "pass"]);
end
end
