function ok = testArtifactFinalizationStatusGate()
%TESTARTIFACTFINALIZATIONSTATUSGATE Publication failure cannot remain green.

base = localStatus();
failed = struct("Executed", true, "Enabled", true, "Ok", false, ...
    "Status", "FAIL", "ContractCount", 27, "FailureCount", 5, ...
    "RequiredFailureCount", 3, ...
    "AuditPath", "artifact_generation/artifact_generation_results.csv", ...
    "FailurePath", "artifact_generation/artifact_generation_failures.csv", ...
    "ErrorIdentifier", "sixgr:artifact:RequiredArtifactGenerationFailed", ...
    "ErrorMessage", "three required artifacts are unavailable");
reduced = sixgr.artifact.applyFinalizationGate(base, failed);
assert(reduced.ExecutionCompleted && reduced.ScenarioObjectiveOk && ...
    reduced.StandardsConformanceOk, ...
    "Artifact publication must not rewrite independent execution/PHY verdicts.");
assert(~reduced.ResultOk && ~reduced.PublicationQualified && ...
    ~reduced.ArtifactCompletenessOk && ~reduced.StrictAnchorPass);
assert(reduced.ArtifactContractStatus == "FAIL" && ...
    reduced.ArtifactContractRequiredFailureCount == 3);
assert(any(startsWith(reduced.RequiredFailedCases, ...
    "artifact_contract_finalization:")));

disabled = sixgr.artifact.applyFinalizationGate(base, struct( ...
    "Executed", false, "Enabled", false, "Ok", true, ...
    "Status", "DISABLED_BY_YAML"));
assert(disabled.ArtifactContractStatus == "NOT_APPLICABLE" && ...
    disabled.ResultOk && disabled.PublicationQualified);

passed = sixgr.artifact.applyFinalizationGate(base, struct( ...
    "Executed", true, "Enabled", true, "Ok", true, "Status", "PASS", ...
    "ContractCount", 27, "FailureCount", 0, "RequiredFailureCount", 0));
assert(passed.ArtifactContractGateOk && passed.ResultOk && ...
    passed.PublicationQualified);

root = tempname();
mkdir(fullfile(root, "reports", "csv"));
mkdir(fullfile(root, "reports", "json"));
cleanup = onCleanup(@() localRemove(root)); %#ok<NASGU>
seed = localCanonicalRootStatus();
sixgr.util.csvWriteTable(fullfile(root, "reports", "csv", ...
    "result_status_summary.csv"), struct2table(seed, "AsArray", true), ...
    "PreserveSchema", true);
sixgr.util.jsonWrite(fullfile(root, "reports", "json", ...
    "result_status_summary.json"), seed);
sixgr.artifact.updateRootStatusArtifacts(root, reduced);
persisted = readtable(fullfile(root, "reports", "csv", ...
    "result_status_summary.csv"), "TextType", "string");
assert(~localLogical(persisted.ResultOk(1)) && ...
    string(persisted.ArtifactContractStatus(1)) == "FAIL");
persistedJSON = jsondecode(fileread(fullfile(root, "reports", "json", ...
    "result_status_summary.json")));
assert(~logical(persistedJSON.PublicationQualified) && ...
    string(persistedJSON.ArtifactContractStatus) == "FAIL");

% A malformed JSON peer must fail before the valid CSV is replaced.
csvBefore = fileread(fullfile(root, "reports", "csv", ...
    "result_status_summary.csv"));
sixgr.util.jsonWrite(fullfile(root, "reports", "json", ...
    "result_status_summary.json"), struct("ResultOk", true));
try
    sixgr.artifact.updateRootStatusArtifacts(root, reduced);
    error("testArtifactFinalizationStatusGate:ExpectedMalformedJSONFailure", ...
        "Malformed JSON status unexpectedly passed validation.");
catch cause
    assert(string(cause.identifier) == ...
        "sixgr:truth:ResultStatusPayloadMissingFields");
end
assert(string(fileread(fullfile(root, "reports", "csv", ...
    "result_status_summary.csv"))) == string(csvBefore), ...
    "CSV root status changed before malformed JSON validation failed.");

ok = true;
fprintf("PASS testArtifactFinalizationStatusGate: artifact publication failure is fail-closed and independent.\n");
end

