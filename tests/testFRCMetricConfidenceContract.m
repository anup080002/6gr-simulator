function ok = testFRCMetricConfidenceContract()
%TESTFRCMETRICCONFIDENCECONTRACT Guard TB-cluster FRC statistics.

setup6GRSimToolkit("AddSubfolders", false, "Verbose", false, ...
    "RunToolboxChecks", false);

confidence = 0.95;

% Seeing only first-attempt successes does not make a four-attempt HARQ
% experiment binomial. The known configured support must keep the interval
% nondegenerate and must not report Clopper-Pearson.
delivered = ones(8, 1);
attempts = ones(8, 1);
[lower, upper, oneLower, oneUpper, method] = ...
    sixgr.conformance.metricConfidenceBounds( ...
    "fraction_of_maximum_throughput", sum(delivered), sum(attempts), ...
    delivered, attempts, confidence, 4);
assert(contains(method, "cluster_ratio_hoeffding_known_support"), ...
    "Four-attempt HARQ must use the independent-TB cluster-ratio bound.");
assert(~contains(method, "clopper_pearson"), ...
    "Observed first-attempt successes must not select binomial confidence.");
assert(lower < 1 && oneLower < 1 && upper == 1 && oneUpper == 1, ...
    ["Known-support HARQ bounds must retain uncertainty when a short sample " ...
    "contains only first-attempt successes."]);

% A genuinely single-transmission experiment is Bernoulli at the TB level.
singleDelivered = [1; 0; 1; 1; 0; 1];
singleAttempts = ones(size(singleDelivered));
[singleLower, singleUpper, ~, ~, singleMethod] = ...
    sixgr.conformance.metricConfidenceBounds( ...
    "fraction_of_maximum_throughput", sum(singleDelivered), ...
    sum(singleAttempts), singleDelivered, singleAttempts, confidence, 1);
assert(contains(singleMethod, ...
    "clopper_pearson_single_transmission_independent_transport_blocks"), ...
    "Configured one-transmission throughput should use TB-level Clopper-Pearson.");
assert(singleLower < mean(singleDelivered) && ...
    singleUpper > mean(singleDelivered), ...
    "The single-transmission interval must contain its TB success estimate.");

% Nondegenerate multi-attempt clusters use the ratio influence function,
% never a transmission-level binomial denominator.
clusterDelivered = [1; 1; 0; 1; 0; 1; 1; 0];
clusterAttempts = [1; 2; 4; 1; 4; 3; 1; 4];
theta = sum(clusterDelivered) / sum(clusterAttempts);
[clusterLower, clusterUpper, ~, ~, clusterMethod] = ...
    sixgr.conformance.metricConfidenceBounds( ...
    "fraction_of_maximum_throughput", sum(clusterDelivered), ...
    sum(clusterAttempts), clusterDelivered, clusterAttempts, confidence, 4);
assert(contains(clusterMethod, "cluster_ratio_delta_method") && ...
    ~contains(clusterMethod, "clopper_pearson"), ...
    "Conditional HARQ transmissions must be analyzed as per-TB clusters.");
assert(clusterLower <= theta && theta <= clusterUpper, ...
    "The cluster-ratio interval must contain its point estimate.");

% BLER remains one Bernoulli event per independently sampled TB.
[blerLower, blerUpper, ~, ~, blerMethod] = ...
    sixgr.conformance.metricConfidenceBounds( ...
    "block_error_rate", 2, 20, [], [], confidence, 1);
assert(blerMethod == "clopper_pearson_independent_transport_blocks", ...
    "BLER must retain TB-level Clopper-Pearson confidence.");
assert(blerLower < 0.1 && blerUpper > 0.1, ...
    "The BLER interval must contain its 2/20 point estimate.");

targetBLER = 1e-5;
twoSidedZeroErrorN = ceil( ...
    log((1 - confidence) / 2) / log(1 - targetBLER));
oneSidedZeroErrorN = ceil( ...
    log(1 - confidence) / log(1 - targetBLER));
[~, twoSidedUpper] = sixgr.conformance.metricConfidenceBounds( ...
    "block_error_rate", 0, twoSidedZeroErrorN, [], [], ...
    confidence, 1);
[~, undersizedUpper] = sixgr.conformance.metricConfidenceBounds( ...
    "block_error_rate", 0, oneSidedZeroErrorN, [], [], ...
    confidence, 1);
assert(twoSidedUpper <= targetBLER && undersizedUpper > targetBLER, ...
    ["The two prespecified project-bracket endpoint decisions need a " ...
    "Bonferroni simultaneous bound; the single-point one-sided count is " ...
    "insufficient for that joint crossing claim."]);

localAssertError(@() sixgr.conformance.metricConfidenceBounds( ...
    "fraction_of_maximum_throughput", 1, 5, [1; 0], [1; 5], ...
    confidence, 4), ...
    "sixgr:conformance:HARQAttemptsExceedConfiguredMaximum");

runnerPath = which("sixgr.conformance.runFRCPoint");
assert(strlength(string(runnerPath)) > 0, ...
    "The FRC runner must be discoverable on the MATLAB path.");
runnerSource = fileread(runnerPath);
assert(~isempty(regexp(runnerSource, ...
    "cfg\.run\.useMex\s*=\s*false", "once")) && ...
    ~isempty(regexp(runnerSource, ...
    "cfg\.phy\.ldpc\.useMexBatchDecode\s*=\s*false", "once")), ...
    "FRC execution must remain on the MATLAB LDPC truth decoder.");
assert(~contains(runnerSource, ...
    '"QualificationBounds", "one_sided_clopper_pearson"'), ...
    "Crossing metadata must not hardcode Clopper-Pearson for HARQ throughput.");
assert(contains(runnerSource, "ConfidenceHalfWidth") && ...
    contains(runnerSource, "PrecisionTargetMet") && ...
    contains(runnerSource, ...
    '"RequiredPointHalfWidthUsedForQualification", false') && ...
    contains(runnerSource, ...
    "fixed_max_transport_blocks_prespecified_snr_tolerance_bracket") && ...
    ~contains(runnerSource, ...
    "all(precisionTargetMet(bracket:bracket+1))"), ...
    ["FRC runs must expose metric precision descriptively while the fixed " ...
    "SNR tolerance bracket, not both metric half-widths, qualifies crossing."]);

fprintf("FRCMetricConfidenceContract: TB-level BLER and clustered HARQ bounds passed.\n");
ok = true;
end

function localAssertError(action, expectedIdentifier)
caught = false;
try
    action();
catch err
    caught = true;
    assert(string(err.identifier) == string(expectedIdentifier), ...
        "Expected error '%s', got '%s'.", ...
        string(expectedIdentifier), string(err.identifier));
end
assert(caught, "Expected error '%s' was not raised.", string(expectedIdentifier));
end
