function ok = testLinkAdaptationFeedbackDelayAuthority()
%TESTLINKADAPTATIONFEEDBACKDELAYAUTHORITY Numeric YAML delay is causal authority.

setup6GRSimToolkit("Verbose", false);
cfg = sixgr.config.defaultConfig();
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.mode", "amc");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.dlPolicy", "baseline");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.ulPolicy", "baseline");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.rankPolicy", "fixed");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.beamPolicy", "fixed");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.feedbackDelaySlots", 2);
cfg = sixgr.util.structSet(cfg, "phy.csi.feedbackDelaySlots", 2);
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.delayModel", "zero");

% Initial operating point must be executed from its own YAML authority;
% configuring AMC does not make a pre-feedback transmission CQI-derived.
bootstrap=cfg;
bootstrap.phy.linkAdaptation.initialMCSIndex=1;
bootstrap.phy.linkAdaptation.maximumMCSIndex=28;
bootstrap.phy.linkAdaptation.ulPolicy="baseline";
bootstrap.phy.pdsch.mcsIndex=10;
bootstrap.phy.pusch.mcsIndex=10;
for direction=["DL","UL"]
    if direction=="DL", family="pdsch"; other="pusch"; policyField="dlPolicy";
    else, family="pusch"; other="pdsch"; policyField="ulPolicy"; end
    expected=sixgr.link.resolveMCSProfile(sixgr.link.resolveConfiguredMCSTable(bootstrap,direction),1);
    [initial,initialState,initialEvent]=sixgr.link.updateLinkAdaptationState( ...
        bootstrap,struct(),direction,1,"Phase","before");
    assert(initial.phy.(family).mcsIndex==1 && ...
        string(initial.phy.(family).modulation)==string(expected.Modulation) && ...
        initial.phy.(family).codeRate==expected.TargetCodeRate);
    assert(isequaln(initial.phy.(other),bootstrap.phy.(other)));
    assert(initialEvent.BootstrapInEffect && ~initialEvent.Applied && ...
        ~initialEvent.DecisionInEffect && isnan(initialEvent.FeedbackSourceSlot));
    [heldInitial,~,heldInitialEvent]=sixgr.link.updateLinkAdaptationState( ...
        bootstrap,initialState,direction,2,"Phase","before");
    assert(isequaln(heldInitial,initial) && heldInitialEvent.BootstrapInEffect);
    fixed=bootstrap; fixed.phy.linkAdaptation.(policyField)="fixed";
    [fixedOut,~,fixedEvent]=sixgr.link.updateLinkAdaptationState(fixed,struct(),direction,1);
    assert(isequaln(fixedOut,fixed) && ~fixedEvent.BootstrapInEffect, ...
        'Fixed operating points must not be overwritten by the adaptive bootstrap.');
    for invalid=[-1,1.5,99]
        malformed=bootstrap; malformed.phy.linkAdaptation.initialMCSIndex=invalid;
        localAssertError(@()sixgr.link.updateLinkAdaptationState( ...
            malformed,struct(),direction,1),"sixgr:link:LinkAdaptation:InvalidInitialMCS");
    end
end

delay = sixgr.link.resolveLinkAdaptationFeedbackDelay(cfg);
assert(delay.FeedbackDelaySlots == 2 && ...
    contains(string(delay.Source), "feedbackDelaySlots") && ...
    ~delay.LegacyDelayCoerced, ...
    "Numeric YAML feedback_delay_slots must override the legacy delay token.");

metrics = struct("CQI", 12, "RI", 1, ...
    "CombinedDecodeOK", true, "AckObserved", true, ...
    "AckObservedValid", true);
[~, state, scheduled] = sixgr.link.updateLinkAdaptationState( ...
    cfg, struct(), "DL", 10, "Phase", "after", "Metrics", metrics);
assert(scheduled.Scheduled && scheduled.ApplySlot == 12 && ...
    scheduled.FeedbackSourceSlot == 10 && ...
    scheduled.ConfiguredFeedbackDelaySlots == 2, ...
    "A slot-10 observation with two-slot delay must be scheduled for slot 12.");
[~, state, held] = sixgr.link.updateLinkAdaptationState( ...
    cfg, state, "DL", 11, "Phase", "before");
assert(~held.Applied, "The decision must remain in flight at slot 11.");
assert(~held.DecisionInEffect, "In-flight feedback cannot own the bootstrap operating point.");
[cfgApplied, stateApplied, applied] = sixgr.link.updateLinkAdaptationState( ...
    cfg, state, "DL", 12, "Phase", "before");
assert(applied.Applied && applied.FeedbackSourceSlot == 10 && ...
    applied.FeedbackAgeSlots == 2 && ...
    double(sixgr.util.structGet(cfgApplied, ...
    "phy.linkAdaptation.lastDecision.FeedbackSourceSlot", NaN)) == 10, ...
    "The applied decision must retain exact source-slot and age lineage.");
assert(applied.DecisionInEffect, "Newly applied feedback must own the operating point.");
assert(~applied.BootstrapInEffect, "Delivered feedback replaces bootstrap ownership.");
[cfgHeld, retainedState, retained] = sixgr.link.updateLinkAdaptationState( ...
    cfgApplied, stateApplied, "DL", 13, "Phase", "before");
assert(~retained.Applied && retained.DecisionInEffect && ...
    retained.ApplySlot == 12 && retained.FeedbackSourceSlot == 10 && ...
    retained.FeedbackAgeSlots == 3 && isequaln(cfgHeld,cfgApplied) && ...
    isequaln(retained.Decision,applied.Decision), ...
    "A held operating point must retain its causal decision, not claim a new update or bootstrap.");
[~, unchangedState, unchanged] = sixgr.link.updateLinkAdaptationState( ...
    cfgHeld, retainedState, "DL", 13, "Phase", "after", "Metrics", metrics);
assert(~unchanged.Scheduled && string(unchanged.Reason)=="no_change" && ...
    isequaln(unchangedState.ActiveDecision,retainedState.ActiveDecision), ...
    "An unchanged operating point must not manufacture a replacement decision.");
% Exercise replacement timing with a genuinely different received CQI.
% Repeating CQI 12 above intentionally produces no new operating point.
changedMetrics=metrics;
changedMetrics.CQI=4;
[~, pendingState, next] = sixgr.link.updateLinkAdaptationState( ...
    cfgHeld, retainedState, "DL", 13, "Phase", "after", "Metrics", changedMetrics);
assert(next.Scheduled && next.ApplySlot == 15);
[~, pendingState, beforeNext] = sixgr.link.updateLinkAdaptationState( ...
    cfgHeld,pendingState,"DL",14,"Phase","before");
assert(~beforeNext.Applied && beforeNext.DecisionInEffect && beforeNext.FeedbackSourceSlot == 10, ...
    "A future decision must not replace the active feedback before delivery.");
[~, ~, afterNext] = sixgr.link.updateLinkAdaptationState( ...
    cfgHeld,pendingState,"DL",15,"Phase","before");
assert(afterNext.Applied && afterNext.DecisionInEffect && afterNext.FeedbackSourceSlot == 13);
badRetained = stateApplied;
badRetained.ActiveDecision.SourceSlot = 14;
localAssertError(@()sixgr.link.updateLinkAdaptationState( ...
    cfgApplied,badRetained,"DL",13,"Phase","before"), ...
    "sixgr:link:LinkAdaptation:InvalidRetainedDecision");
legacyState = rmfield(stateApplied,"ActiveDecision");
[~,~,unknown] = sixgr.link.updateLinkAdaptationState( ...
    cfgApplied,legacyState,"DL",13,"Phase","before");
assert(~unknown.DecisionInEffect, "Legacy state without retained lineage must not manufacture it.");

% UL shares the state machine but owns a separate PUSCH operating point.
[~, ulState, ulScheduled] = sixgr.link.updateLinkAdaptationState( ...
    cfg,struct(),"UL",10,"Phase","after","Metrics",metrics);
assert(ulScheduled.Scheduled);
[ulCfg,ulState,ulApplied] = sixgr.link.updateLinkAdaptationState( ...
    cfg,ulState,"UL",12,"Phase","before");
[ulHeldCfg,~,ulHeld] = sixgr.link.updateLinkAdaptationState( ...
    ulCfg,ulState,"UL",13,"Phase","before");
assert(ulApplied.Applied && ~ulHeld.Applied && ulHeld.DecisionInEffect && ...
    ulHeld.FeedbackSourceSlot == 10 && ulHeld.FeedbackAgeSlots == 3 && ...
    isequaln(ulHeldCfg,ulCfg) && isequaln(ulHeld.Decision,ulApplied.Decision), ...
    "PUSCH must retain its own causal operating-point lineage between feedback updates.");
localAssertError(@()sixgr.link.updateLinkAdaptationState( ...
    ulCfg,ulState,"DL",13,"Phase","before"), ...
    "sixgr:link:LinkAdaptation:InvalidRetainedDecision");

cfgMismatch = sixgr.util.structSet(cfg, ...
    "phy.csi.feedbackDelaySlots", 3);
localAssertError(@()sixgr.link.resolveLinkAdaptationFeedbackDelay(cfgMismatch), ...
    "sixgr:link:FeedbackDelayAuthorityMismatch");

cfgLegacy = sixgr.config.defaultConfig();
cfgLegacy = sixgr.util.structSet(cfgLegacy, ...
    "phy.linkAdaptation.delayModel", "zero");
legacy = sixgr.link.resolveLinkAdaptationFeedbackDelay(cfgLegacy);
assert(legacy.FeedbackDelaySlots == 1 && ...
    legacy.RequestedFeedbackDelaySlots == 0 && ...
    legacy.LegacyDelayCoerced, ...
    "A legacy zero-delay token must disclose the causal one-slot minimum.");

ok = true;
end

function localAssertError(fcn, expectedIdentifier)
threw = false;
try
    fcn();
catch ME
    threw = true;
    assert(strcmp(ME.identifier, expectedIdentifier), ...
        "Expected %s but received %s.", expectedIdentifier, ME.identifier);
end
assert(threw, "Expected error %s was not raised.", expectedIdentifier);
end
