function tests = testRAFixedSNRPowerReferenceAuthority
tests = functiontests(localfunctions);
end

function testAbsolutePowerIsRejectedInsideFixedSNRSweep(testCase)
cfg = local5MHzConfig();
cfg.integration.power_reference_mode = 'absolute_calibrated_sqrt_mw';
verifyError(testCase, @()sixgr.rf.fixedSNRPowerReferenceMode(cfg), ...
    "sixgr:rf:MixedFixedSNRAndAbsolutePower");
end

function testNormalizedFixedSNRKeepsUnitREAuthority(testCase)
cfg = local5MHzConfig();
verifyTrue(testCase, sixgr.rf.isNormalizedFixedSNRPowerReference(cfg));

[prepared, checkpoint] = localPrepareSharedMsg1(cfg);
tx = prepared.PreparedTransmission;
ctx = tx.PowerContext;
verifyFalse(testCase, logical(ctx.PhysicalDevicePowerClaim));
verifyEqual(testCase, double(ctx.AmplitudeScale), 1, 'AbsTol', 0);
verifyEqual(testCase, string(ctx.TotalTxPowerSource), ...
    "fixed_snr_unit_occupied_re_reference_not_device_power");
verifyTrue(testCase, isnan(double(prepared.PreambleTxPower_dBm)));
verifyEqual(testCase, string(checkpoint.PowerState.PowerControlStatus), ...
    "not_applied_normalized_fixed_esn0_unit_occupied_re_es");
end

function testThermalLinkBudgetAcceptsAbsolutePower(testCase)
root = fileparts(fileparts(mfilename('fullpath')));
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile(root, ...
    'simulator','configs','scenarios', ...
    'lls_2ghz_20mhz_rank2_cdlc_o2i_thermal.yaml'));
cfg = sixgr.lls6g.buildInternalConfig(scenario,tempname);
verifyFalse(testCase, sixgr.rf.isFixedSNRLinkAuthority(cfg));
verifyEqual(testCase, sixgr.rf.fixedSNRPowerReferenceMode(cfg), ...
    "absolute_calibrated_sqrt_mw");
end

function [prepared, checkpoint] = localPrepareSharedMsg1(cfg)
carrier = sixgr.phy.grid.makeCarrier(cfg);
ofdm = nrOFDMInfo(carrier);
common = struct('Source','decoded_sib1', ...
    'TimingAdvanceOffsetPresent',false,'TimingAdvanceOffset','');
cfg.SharedULTimingContext = struct( ...
    'DLReference',struct( ...
    'Source','received_SSB_timing_and_decoded_BCH', ...
    'SampleRateHz',double(ofdm.SampleRate), ...
    'DLPhaseOffsetSamples',0,'AvailableAtSample',0), ...
    'Offset',sixgr.phy.frame.resolveULTimingAdvanceOffset(common,'FR1'));
[prepared, checkpoint] = sixgr.phy.ra.runFourStepRA(cfg, ...
    'WriteArtifacts', false, ...
    'RuntimeIntegrationMode', 'shared_physical_waveform_stream', ...
    'UseRuntimeChannel', true, ...
    'RequireRuntimeStageWaveforms', true, ...
    'AllowRuntimeStageWaveformComposition', false, ...
    'StageAction', 'prepare_next_stage');
end

function cfg = local5MHzConfig()
