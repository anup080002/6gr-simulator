function modText = localModulationFromOrder(order)
switch round(double(order))
    case 2
        modText = "QPSK";
    case 4
        modText = "16QAM";
    case 6
        modText = "64QAM";
    case 8
        modText = "256QAM";
    otherwise
        modText = "QPSK";
end
end
