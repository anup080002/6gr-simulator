function ok = testLLSRuntimeTruthContractGates()
%TESTLLSRUNTIMETRUTHCONTRACTGATES Run-level status must fail without honest evidence.

setup6GRSimToolkit("Verbose", false);

scfg = sixgr.lls6g.config.loadScenarioConfig("simulator/configs/scenarios/lls_100mhz_tdlc_bidirectional_truth.yaml");
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tempdir, "lls_truth_contract_cfg"));

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>
layout = sixgr.report.resultLayout(tmp);
localEnsureLayout(layout);

missingVerdict = sixgr.truth.evaluateLLSRuntimeTruthContract(tmp, scfg, cfg);
assert(~logical(missingVerdict.Ok), "Empty run folders must not pass the LLS runtime truth contract.");
assert(double(missingVerdict.CanonicalArtifactGapCount) > 0, ...
    "Missing canonical artifacts must contribute to the truth-contract failure count.");
assert(double(missingVerdict.RequiredRuntimeEvidenceMissingCount) > 0, ...
    "Missing required DL/UL runtime evidence must fail the truth contract.");

passCtx = llsRootGateFixture("pass");
passingVerdict = sixgr.truth.evaluateLLSRuntimeTruthContract(passCtx.RunFolder, passCtx.ScenarioConfig, passCtx.InternalConfig);
assert(logical(passingVerdict.Ok), "Complete strict root-gate evidence must pass.");
assert(double(passingVerdict.RoundtripMismatchCount) == 0, ...
    "Consistent roundtrip artifacts must not produce mismatch failures.");
assert(double(passingVerdict.RequiredRuntimeEvidenceMissingCount) == 0, ...
    "Nonempty required DL/UL trial artifacts must satisfy required runtime evidence.");
summaryTruthT = readtable(fullfile(passCtx.Layout.ReportCSVDir, "truth_contract_summary.csv"), "VariableNamingRule", "preserve");
failureTruthT = readtable(fullfile(passCtx.Layout.ReportCSVDir, "truth_contract_failures.csv"), "VariableNamingRule", "preserve");
assert(height(summaryTruthT) == 1 && logical(summaryTruthT.RuntimeTruthContractOk(1)), ...
    "Truth-contract evaluator must emit a passing truth_contract_summary.csv row.");
assert(height(failureTruthT) == 0, ...
    "Passing truth contract must emit an empty, schema-only truth_contract_failures.csv table without fake failure rows.");
assert(logical(summaryTruthT.NoProxyPHYOk(1)) && logical(summaryTruthT.SyntheticBLERFallbackOk(1)), ...
    "Truth contract summary must explicitly prove no proxy/synthetic-BLER path is active.");
assert(logical(summaryTruthT.RawLifecycleOk(1)) && logical(summaryTruthT.FERRunScopeIdentityOk(1)) && logical(summaryTruthT.AMCNamingOk(1)), ...
    "Truth contract summary must expose raw lifecycle, FER scope, and AMC naming checks.");

lifecycleCtx = llsRootGateFixture("pass");
lifecycleSummaryT = readtable(fullfile(lifecycleCtx.Layout.ReportCSVDir, "scenario_summary.csv"), "VariableNamingRule", "preserve");
if iscell(lifecycleSummaryT.RunCompletion)
    lifecycleSummaryT.RunCompletion(:) = {"not_completed"};
else
    lifecycleSummaryT.RunCompletion(:) = repmat("not_completed", height(lifecycleSummaryT), 1);
end
lifecycleSummaryT.Ok(:) = false;
lifecycleSummaryT.ResultOk(:) = false;
sixgr.util.csvWriteTable(fullfile(lifecycleCtx.Layout.ReportCSVDir, "scenario_summary.csv"), lifecycleSummaryT);
rootBlockedVerdict = sixgr.truth.evaluateLLSRuntimeTruthContract(lifecycleCtx.RunFolder, lifecycleCtx.ScenarioConfig, lifecycleCtx.InternalConfig);
assert(~logical(rootBlockedVerdict.Ok), ...
    "Canonical root ResultOk=false must block the runtime truth contract even when low-level evidence rows exist.");
assert(any(contains(string(rootBlockedVerdict.Failures), "root_result_status_failed")), ...
    "Truth-contract failures must include the canonical root-status failure reason.");
rootBlockedSummaryT = readtable(fullfile(lifecycleCtx.Layout.ReportCSVDir, "truth_contract_summary.csv"), "VariableNamingRule", "preserve");
assert(~logical(rootBlockedSummaryT.ResultOk(1)) && ~logical(rootBlockedSummaryT.RuntimeTruthContractOk(1)), ...
    "Truth-contract summary must publish the canonical root-gate failure.");

proxyCtx = llsRootGateFixture("pass");
runtimeT = readtable(fullfile(proxyCtx.Layout.ReportCSVDir, "runtime_operating_mode.csv"), "VariableNamingRule", "preserve");
runtimeT.InterferenceMode(:) = repmat({"abstract_scheduler_context"}, height(runtimeT), 1);
sixgr.util.csvWriteTable(fullfile(proxyCtx.Layout.ReportCSVDir, "runtime_operating_mode.csv"), runtimeT);
proxyVerdict = sixgr.truth.evaluateLLSRuntimeTruthContract(proxyCtx.RunFolder, proxyCtx.ScenarioConfig, proxyCtx.InternalConfig);
assert(~logical(proxyVerdict.Ok), "Abstract/proxy interference modes must fail honest LLS truth gating.");
assert(double(proxyVerdict.StrictProxyGuardFailureCount) > 0, ...
    "Proxy/interference violations must be counted separately from raw evidence gaps.");

fixedCtx = llsRootGateFixture("pass");
fixedScenario = fixedCtx.ScenarioConfig;
if isa(fixedScenario, "sixgr.lls6g.config.ScenarioConfig")
    fixedScenario = fixedScenario.toStruct();
end
fixedScenario = sixgr.util.structSet( ...
    fixedScenario, "validation.run_class", "fixed_snr_sweep_lls");
fixedScenario = sixgr.util.structSet( ...
    fixedScenario, "validation.fixed_snr_sweep_required", true);
fixedScenario = sixgr.util.structSet( ...
    fixedScenario, "validation.fixed_link_campaign.enabled", true);
fixedScenario = sixgr.util.structSet( ...
    fixedScenario, ...
    "validation.fixed_link_campaign.disable_auxiliary_signals", true);
fixedScenario = sixgr.util.structSet( ...
    fixedScenario, ...
    "sweeps_and_matrix.fixed_link_calibration.only", true);
fixedCfg = fixedCtx.InternalConfig;
fixedCfg = sixgr.util.structSet( ...
    fixedCfg, "validation.run_class", "fixed_snr_sweep_lls");
fixedCfg = sixgr.util.structSet( ...
    fixedCfg, "validation.fixed_snr_sweep_required", true);
fixedCfg = sixgr.util.structSet( ...
    fixedCfg, "validation.fixed_link_campaign.enabled", true);
fixedCfg = sixgr.util.structSet( ...
    fixedCfg, ...
    "validation.fixed_link_campaign.disable_auxiliary_signals", true);
fixedCfg = sixgr.util.structSet( ...
    fixedCfg, "run.fixedLinkCampaignOnly", true);
% Reproduce the real runner state where the internal cfg retains a
% conservative derived scenario class. The explicit YAML validation class
% must remain authoritative over that derived value.
fixedCfg = sixgr.util.structSet( ...
    fixedCfg, "scenario.run_class", "adaptive_system_diagnostic");

delete(fullfile(fixedCtx.Layout.PacketFlowCSVDir, ...
    "live_dl_scheduler_grants.csv"));
delete(fullfile(fixedCtx.Layout.PacketFlowCSVDir, ...
    "live_ul_scheduler_grants.csv"));
delete(fullfile(fixedCtx.Layout.ReportCSVDir, ...
    "live_error_rate_summary.csv"));
distancePath = fullfile(fixedCtx.Layout.AirInterfaceCSVDir, ...
    "distance_vs_sinr.csv");
if isfile(distancePath)
    delete(distancePath);
end
dlFixed = readtable(fullfile(fixedCtx.Layout.AirInterfaceCSVDir, ...
    "dl_pdsch_trials.csv"), "VariableNamingRule", "preserve");
dlFixed.CRCPass(:) = false;
dlFixed.BitErrors(:) = 10;
sixgr.util.csvWriteTable(fullfile(fixedCtx.Layout.AirInterfaceCSVDir, ...
    "dl_pdsch_trials.csv"), dlFixed);

fixedVerdict = sixgr.truth.evaluateLLSRuntimeTruthContract( ...
    fixedCtx.RunFolder, fixedScenario, fixedCfg);
assert(logical(fixedVerdict.Ok), ...
    ["A fixed-SNR waveform sweep with real canonical DL/UL trials must " ...
    "not require fabricated scheduler grants, run-scope FER, geometry " ...
    "distance, SIB1, or one aggregate BLER threshold across outage and " ...
    "pass points."]);
assert(string(fixedVerdict.CheckDetails.FER.FERScopeStatus) == ...
    "not_applicable_for_fixed_snr_sweep" && ...
    ~logical(fixedVerdict.CheckDetails.MeasuredSINR.DistanceSINRApplicable) && ...
    string(fixedVerdict.CheckDetails.PDSCHObjective.Applicability) == ...
    "fixed_snr_sweep_audit", ...
    "Fixed-sweep applicability must be explicit in truth-contract details.");
fixedClass = readtable(fullfile(fixedCtx.Layout.ReportCSVDir, ...
    "run_classification.csv"), "VariableNamingRule", "preserve", ...
    "TextType", "string");
assert(string(fixedClass.RunClass(1)) == "fixed_snr_sweep_lls", ...
    ["Operator-owned validation.run_class must outrank a derived internal " ...
     "cfg.scenario.run_class value."]);

% The production runner passes a ScenarioConfig object, not the plain
% structure used above. Preserve the exact same operator-owned run class
% through that object path as well.
fixedScenarioObject = sixgr.lls6g.config.ScenarioConfig(fixedScenario, ...
    "SourceFiles", strings(0,1), "ConfigPath", "unit_test", ...
    "ConfigHash", "unit_test", "Kind", "scenario");
fixedObjectVerdict = sixgr.truth.evaluateLLSRuntimeTruthContract( ...
    fixedCtx.RunFolder, fixedScenarioObject, fixedCfg);
assert(logical(fixedObjectVerdict.Ok), ...
    "ScenarioConfig-object fixed-sweep evaluation must retain the truth verdict.");
fixedObjectClass = readtable(fullfile(fixedCtx.Layout.ReportCSVDir, ...
    "run_classification.csv"), "VariableNamingRule", "preserve", ...
    "TextType", "string");
assert(string(fixedObjectClass.RunClass(1)) == "fixed_snr_sweep_lls", ...
    ["ScenarioConfig-object evaluation must preserve the operator-owned " ...
     "fixed_snr_sweep_lls declaration."]);

ok = true;
end

function localEnsureLayout(layout)
fields = ["ReportCSVDir", "AirInterfaceCSVDir", "PacketFlowCSVDir"];
for ii = 1:numel(fields)
    sixgr.util.ensureDir(layout.(fields(ii)));
end
end

