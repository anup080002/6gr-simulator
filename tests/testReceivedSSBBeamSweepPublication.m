function ok=testReceivedSSBBeamSweepPublication(retainedRun)
% Authored table-contract fixture; optional read-only actual-run verification.
% Does not claim a new physical acquisition or alter retained source files.
setup6GRSimToolkit('Verbose',false);
runtime=string(fileread(which('sixgr.truth.CoupledTruthRuntime')));
assert(contains(runtime,'sixgr.truth.exportReceivedSSBBeamSweep(string(runFolder),receivedBeams)'), ...
    'Live/failed-run table publication must retain the actual received beam candidates.');
catalog=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_causal_access_to_data_wiring_tdd.yaml');
catalogText=string(jsonencode(catalog));
assert(contains(catalogText,'beamforming/csv/ssb_beam_sweep.csv') && ...
    contains(catalogText,'SelectedSSBIndex') && contains(catalogText,'SelectionSource'), ...
    'The causal audit must consume the actual received SSB selection schema.');
folder=string(tempname); mkdir(folder);
cleanup=onCleanup(@()rmdir(folder,'s')); %#ok<NASGU>
t=table((0:3).',repmat(2,4,1),[false;false;true;false], ...
    [true;false;true;true],[-14;-18;-11;-16], ...
    repmat("declared_table_fixture",4,1),repmat("fixture_execution",4,1), ...
    repmat("fixture_config",4,1),repmat("in_path",4,1),true(4,1), ...
    false(4,1),false(4,1), ...
    'VariableNames',{'SSBIndex','SelectedSSBIndex','SelectedBeamFlag', ...
    'CRCPass','SS_RSRP_dB_re_UnitOccupiedRE_Es','RunID','ExecutionID', ...
    'ConfigHash','EvidenceScope','SameScenarioInPathEligible', ...
    'FallbackFlag','PlaceholderFlag'});
before=rng;
out=sixgr.truth.exportReceivedSSBBeamSweep(folder,t);
assert(isequaln(t,out) && isequal(rng,before));
layout=sixgr.report.resultLayout(folder);
paths=[fullfile(layout.AirInterfaceCSVDir,'ssb_pbch_sib1_beam_sweep.csv'), ...
    fullfile(layout.ControlCSVDir,'ssb_pbch_sib1_beam_sweep.csv'), ...
    fullfile(layout.BeamformingCSVDir,'ssb_pbch_sib1_beam_sweep.csv'), ...
    fullfile(layout.BeamformingCSVDir,'ssb_beam_sweep.csv')];
for path=paths
    actual=sixgr.util.csvReadTable(path,'TextType','string');
    assert(height(actual)==4 && isequal(actual.SSBIndex,t.SSBIndex) && ...
        isequal(actual.SS_RSRP_dB_re_UnitOccupiedRE_Es,t.SS_RSRP_dB_re_UnitOccupiedRE_Es) && ...
        isequal(logical(actual.CRCPass),t.CRCPass) && ...
        isequal(logical(actual.SelectedBeamFlag),t.SelectedBeamFlag));
end
bad=t; bad.EvidenceScope(:)="standalone_diagnostic";
reject(@()sixgr.truth.exportReceivedSSBBeamSweep(folder,bad), ...
    'sixgr:truth:NonRuntimeSSBBeamEvidence');
bad=t; bad.ExecutionID(4)="unrelated_run";
reject(@()sixgr.truth.exportReceivedSSBBeamSweep(folder,bad), ...
    'sixgr:truth:MixedSSBBeamEvidenceIdentity');
bad=t; bad.FallbackFlag(1)=true;
reject(@()sixgr.truth.exportReceivedSSBBeamSweep(folder,bad), ...
    'sixgr:truth:NonRuntimeSSBBeamEvidence');
empty=sixgr.truth.exportReceivedSSBBeamSweep(folder,t([],:));
assert(isempty(empty));
% Declared publication-contract fixture, not an authenticated PHY run:
% eight actual search results may include four silent requested candidates.
% Search count must never replace the separate transmitted-beam count.
search=t([1:4 1:4],:);
search.SSBIndex=[(0:3).';nan(4,1)];
search.RequestedSSBOccasionIndex=(0:7).';
search.SelectedBeamFlag=false(8,1); search.SelectedBeamFlag(3)=true;
search.CRCPass=[1;0;1;1;NaN;NaN;NaN;NaN];
search.BCHDecodeAttempted=[true(4,1);false(4,1)];
search.SS_RSRP_dB_re_UnitOccupiedRE_Es(5:8)=NaN;
search.RNTI=ones(8,1);
search.ObservationStartSample=zeros(8,1);
search.ObservationEndSampleExclusive=repmat(4096,8,1);
search.ObservationSampleRateHz=repmat(30720000,8,1);
search.ReceiverObservationSHA256=repmat(string(repmat('a',1,64)),8,1);
search.SSBBurstActiveIndices0Based=repmat("[0,1,2,3]",8,1);
search.SSBBurstConfiguredBeamCount=repmat(4,8,1);
search.SSBBurstExecutedBeamCount=repmat(4,8,1);
contract=struct('ContractVersion',"sixgr.ssb.initial_acquisition_window/v1", ...
    'Scope',"all_receiver_case_lmax_candidates_not_TX_active_bitmap", ...
    'SHA256',string(repmat('b',1,64)),'Lmax',8,'CandidateIndices',0:7, ...
    'SampleRateHz',30720000,'StartSample',0,'EndSampleExclusive',4096, ...
    'ArchiveEndSampleExclusive',8192);
search.SSBReceiverSearchCandidateCount=repmat(8,8,1);
search.SSBReceiverSearchIndices0Based=repmat("[0,1,2,3,4,5,6,7]",8,1);
search.SSBReceiverSearchComplete=true(8,1);
search.SSBReceiverSearchScope=repmat(contract.Scope,8,1);
search.SSBAcquisitionWindowContractJSON=repmat(string(jsonencode(contract)),8,1);
search.SSBAcquisitionWindowSHA256=repmat(contract.SHA256,8,1);
search.SSBRequestedCandidateTransmitted=[true(4,1);false(4,1)];
out=sixgr.truth.exportReceivedSSBBeamSweep(folder,search);
assert(isequaln(search,out));
for path=paths
    actual=sixgr.util.csvReadTable(path,'TextType','string');
    assert(height(actual)==8 && isequaln(actual.SSBIndex,search.SSBIndex) && ...
        isequal(actual.RequestedSSBOccasionIndex,search.RequestedSSBOccasionIndex) && ...
        isequaln(actual.CRCPass,search.CRCPass) && ...
        isequal(logical(actual.BCHDecodeAttempted),search.BCHDecodeAttempted) && ...
        all(actual.SSBBurstExecutedBeamCount==4) && ...
        sum(actual.SSBRequestedCandidateTransmitted)==4 && ...
        isequal(actual.ObservationStartSample,search.ObservationStartSample) && ...
        isequal(actual.ObservationEndSampleExclusive,search.ObservationEndSampleExclusive) && ...
        isequal(actual.ObservationSampleRateHz,search.ObservationSampleRateHz) && ...
        isequal(actual.ReceiverObservationSHA256,search.ReceiverObservationSHA256) && ...
        isequal(actual.RunID,search.RunID) && isequal(actual.ExecutionID,search.ExecutionID) && ...
        isequal(actual.ConfigHash,search.ConfigHash) && ...
        isequal(actual.SSBAcquisitionWindowContractJSON,search.SSBAcquisitionWindowContractJSON));
end
bad=search; bad.ExecutionID(8)="unrelated_run";
reject(@()sixgr.truth.exportReceivedSSBBeamSweep(folder,bad), ...
    'sixgr:truth:MixedSSBBeamEvidenceIdentity');
bad=search; bad.FallbackFlag(8)=true;
reject(@()sixgr.truth.exportReceivedSSBBeamSweep(folder,bad), ...
    'sixgr:truth:NonRuntimeSSBBeamEvidence');
if nargin>0
    source=fullfile(retainedRun,'air_interface','csv','pbch_trials.csv');
    hash=string(sixgr.util.sha256File(source));
    received=sixgr.util.csvReadTable(source,'TextType','string');
    out=sixgr.truth.exportReceivedSSBBeamSweep(folder,received);
    assert(isequaln(out,received) && string(sixgr.util.sha256File(source))==hash);
    fprintf('RECEIVED_SSB_RETAINED_EXPORT_PASS rows=%d same_run_no_new_waveform=1\n',height(received));
end
ok=true;
end
function reject(fn,id)
try,fn();catch cause,assert(strcmp(cause.identifier,id),cause.message);return;end
error('test:ExpectedRejection','Expected %s.',id);
end
