function ok = testResultIntegrityChecks()
%TESTRESULTINTEGRITYCHECKS Verify result-integrity guards reject mixed or impossible data.

setup6GRSimToolkit("Verbose", false);

results = localValidResultSet();
[T, summary] = sixgr.report.checkResultIntegrity(results, "StrictMode", true, "ContextLabel", "valid_result_set");
assert(summary.Ok && all(logical(T.Pass)), "Valid result set should pass strict integrity checks.");

bad = results;
bad.PacketIntegrityTable.Notes(1) = "fallback_awgn_profile";
[T, summary] = sixgr.report.checkResultIntegrity(bad, "ContextLabel", "mixed_truth_fallback");
assert(~summary.Ok, "Mixed truth/fallback data must fail integrity checks.");
assert(localCheckFailed(T, "mixed_truth_fallback_data"), "Mixed truth/fallback data was not flagged.");
localAssertStrictIntegrityThrow(bad, "mixed_truth_fallback_data");

bad = results;
bad.FlowSummaryTable.DataSemantics(1) = "PROXY_PACKET_MODEL";
[T, summary] = sixgr.report.checkResultIntegrity(bad, "ContextLabel", "mixed_truth_proxy");
assert(~summary.Ok, "Mixed truth/proxy data must fail integrity checks.");
assert(localCheckFailed(T, "mixed_truth_proxy_data"), "Mixed truth/proxy data was not flagged.");
localAssertStrictIntegrityThrow(bad, "mixed_truth_proxy_data");

bad = results;
bad.SummaryTable.Goodput_Mbps = bad.SummaryTable.Goodput_Mbps + 0.01;
[T, summary] = sixgr.report.checkResultIntegrity(bad, "ContextLabel", "inconsistent_summary_totals");
assert(~summary.Ok, "Inconsistent summary totals must fail integrity checks.");
assert(localCheckFailed(T, "inconsistent_summary_totals"), "Inconsistent summary totals were not flagged.");
localAssertStrictIntegrityThrow(bad, "inconsistent_summary_totals");

bad = results;
bad.PacketIntegrityTable.PacketDeliveryRatio(1) = 1.2;
[T, summary] = sixgr.report.checkResultIntegrity(bad, "ContextLabel", "impossible_physical_values");
assert(~summary.Ok, "Impossible physical values must fail integrity checks.");
assert(localCheckFailed(T, "impossible_physical_values"), "Impossible physical values were not flagged.");
localAssertStrictIntegrityThrow(bad, "impossible_physical_values");

ok = true;
end

function tf = localCheckFailed(T, checkName)
mask = string(T.Check) == string(checkName);
tf = any(mask) && any(~logical(T.Pass(mask)));
end

function localAssertStrictIntegrityThrow(results, expectedCheck)
threw = false;
try
    sixgr.report.checkResultIntegrity(results, "StrictMode", true, "ContextLabel", "strict_integrity_case"); %#ok<NASGU>
catch ME
    threw = contains(string(ME.identifier), "sixgr:report:ResultIntegrityFailed") && ...
        contains(string(ME.message), string(expectedCheck));
end
assert(threw, "Strict result-integrity checks must throw for %s.", expectedCheck);
end

