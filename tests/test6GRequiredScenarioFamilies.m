function ok = test6GRequiredScenarioFamilies()
%TEST6GREQUIREDSCENARIOFAMILIES Validate the required 6G scenario-family catalog.

setup6GRSimToolkit("Verbose", false);

repoRoot = fileparts(fileparts(mfilename("fullpath")));
catalogPath = fullfile(repoRoot, "simulator", "configs", "scenario_families", "required_scenario_families.yaml");
assert(isfile(catalogPath), ...
    "sixgr:test:6GScenarioFamilies:MissingCatalog", ...
    "Missing required scenario-family catalog '%s'.", catalogPath);

catalog = sixgr.lls6g.config.readConfigFile(catalogPath);
assert(isfield(catalog, "families"), ...
    "sixgr:test:6GScenarioFamilies:MissingFamilies", ...
    "Scenario-family catalog must define a 'families' collection.");

families = localNormalizeStructList(catalog.families);
requiredIDs = [ ...
    "nr_like_benchmark_baseline"
    "band_700mhz_fdd_coverage"
    "band_2ghz_fdd_baseline"
    "band_4ghz_tdd_baseline"
    "band_7ghz_wideband_high_capacity"
    "band_30ghz_high_band_beam_centric"
    "tracking_rs_synchronization_stress"
    "pdcch_reliability_blind_decoding_blocking"
    "ul_waveform_cp_ofdm_vs_dfts_ofdm"
    "dl_based_csi_acquisition"
    "ul_based_csi_acquisition"
    "joint_dl_ul_csi_acquisition"
    "prach_initial_access_beam_management"
    "harq_latency_reliability_tradeoff"
    "high_order_modulation_and_coding_chain"
    "probabilistic_shaping_distribution_matching"
    "joint_coding_modulation_candidate_studies"
    "ai_demodulation"
    "ai_csi_compression_reporting"
    "energy_efficiency_common_signal_clustering"
    "bandwidth_adaptation_bwp_like_studies"
    "mtrp_sfn_coordinated_transmission"
    "mrss_coexistence_stress"
    "full_duplex_self_interference_candidate_studies"
    ];

assert(numel(families) == numel(requiredIDs), ...
    "sixgr:test:6GScenarioFamilies:UnexpectedCount", ...
    "Expected %d required scenario families, found %d.", numel(requiredIDs), numel(families));

ids = strings(numel(families), 1);
for i = 1:numel(families)
    family = families{i};
    ids(i) = string(family.family_id);
    assert(strlength(ids(i)) > 0, ...
        "sixgr:test:6GScenarioFamilies:EmptyID", ...
        "Scenario-family entry %d is missing family_id.", i);
    assert(isfield(family, "objective") && strlength(string(family.objective)) > 0, ...
        "sixgr:test:6GScenarioFamilies:MissingObjective", ...
        "Scenario family '%s' is missing its objective.", ids(i));
    assert(isfield(family, "baseline_config"), ...
        "sixgr:test:6GScenarioFamilies:MissingBaseline", ...
        "Scenario family '%s' is missing baseline_config.", ids(i));
    assert(isfield(family, "config_packs"), ...
        "sixgr:test:6GScenarioFamilies:MissingConfigPacks", ...
        "Scenario family '%s' is missing config_packs.", ids(i));
    assert(isfield(family, "sweep_definition"), ...
        "sixgr:test:6GScenarioFamilies:MissingSweep", ...
        "Scenario family '%s' is missing sweep_definition.", ids(i));
    assert(isfield(family, "primary_kpis") && ~isempty(family.primary_kpis), ...
        "sixgr:test:6GScenarioFamilies:MissingPrimaryKPIs", ...
        "Scenario family '%s' is missing primary_kpis.", ids(i));
    assert(isfield(family, "optional_kpis") && ~isempty(family.optional_kpis), ...
        "sixgr:test:6GScenarioFamilies:MissingOptionalKPIs", ...
        "Scenario family '%s' is missing optional_kpis.", ids(i));
    assert(isfield(family, "mandatory_plots") && ~isempty(family.mandatory_plots), ...
        "sixgr:test:6GScenarioFamilies:MissingPlots", ...
        "Scenario family '%s' is missing mandatory_plots.", ids(i));
    assert(isfield(family, "pass_fail_expectations") && ~isempty(family.pass_fail_expectations), ...
        "sixgr:test:6GScenarioFamilies:MissingPassFail", ...
        "Scenario family '%s' is missing pass_fail_expectations.", ids(i));
    assert(isfield(family, "typical_debug_traces") && ~isempty(family.typical_debug_traces), ...
        "sixgr:test:6GScenarioFamilies:MissingDebugTraces", ...
        "Scenario family '%s' is missing typical_debug_traces.", ids(i));

    localValidateConfigRef(family.baseline_config, repoRoot, ids(i), "baseline_config");

    packs = localNormalizeStructList(family.config_packs);
    assert(~isempty(packs), ...
        "sixgr:test:6GScenarioFamilies:EmptyConfigPacks", ...
        "Scenario family '%s' must include at least one config pack.", ids(i));
    for k = 1:numel(packs)
        localValidateConfigRef(packs{k}, repoRoot, ids(i), "config_packs");
    end

    dims = localNormalizeStructList(family.sweep_definition.dimensions);
    assert(~isempty(dims), ...
        "sixgr:test:6GScenarioFamilies:MissingDimensions", ...
        "Scenario family '%s' must define at least one sweep dimension.", ids(i));
end

assert(isempty(setdiff(requiredIDs, ids)), ...
    "sixgr:test:6GScenarioFamilies:MissingRequiredFamilies", ...
    "Scenario-family catalog is missing one or more required family ids.");
assert(numel(unique(ids)) == numel(ids), ...
    "sixgr:test:6GScenarioFamilies:DuplicateIDs", ...
    "Scenario-family catalog contains duplicate family ids.");

manifestPath = fullfile(repoRoot, "docs", "6g_lls", "scenario_family_manifest.json");
assert(isfile(manifestPath), ...
    "sixgr:test:6GScenarioFamilies:MissingManifest", ...
    "Missing scenario-family manifest '%s'.", manifestPath);
manifest = jsondecode(fileread(manifestPath));
assert(isfield(manifest, "families") && numel(manifest.families) == numel(requiredIDs), ...
    "sixgr:test:6GScenarioFamilies:ManifestMismatch", ...
    "Scenario-family manifest must contain the same 24 required families.");

ok = true;
end

function arr = localNormalizeStructList(value)
if iscell(value)
    arr = value;
elseif isstruct(value)
    arr = num2cell(value);
else
    arr = value;
end
end

function localValidateConfigRef(ref, repoRoot, familyID, fieldName)
assert(isstruct(ref) && isfield(ref, "path"), ...
    "sixgr:test:6GScenarioFamilies:BadConfigRef", ...
    "Scenario family '%s' has an invalid %s entry.", familyID, fieldName);

pathOnDisk = fullfile(repoRoot, char(string(ref.path)));
assert(isfile(pathOnDisk), ...
    "sixgr:test:6GScenarioFamilies:MissingConfigFile", ...
    "Scenario family '%s' references missing config file '%s'.", familyID, pathOnDisk);

if isfield(ref, "override_label")
    raw = sixgr.lls6g.config.readConfigFile(pathOnDisk);
    overrides = sixgr.util.structGet(raw, "scenario.sweep.overrides", struct([]));
    overrides = localNormalizeStructList(overrides);
    labels = strings(0,1);
    for i = 1:numel(overrides)
        labels(end+1,1) = string(sixgr.util.structGet(overrides{i}, "label", "")); %#ok<AGROW>
    end
    assert(any(labels == string(ref.override_label)), ...
        "sixgr:test:6GScenarioFamilies:MissingOverride", ...
        "Scenario family '%s' references missing override '%s' in '%s'.", ...
        familyID, string(ref.override_label), pathOnDisk);
end
end
