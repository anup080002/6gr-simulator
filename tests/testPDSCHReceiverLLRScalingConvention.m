function ok = testPDSCHReceiverLLRScalingConvention()
%TESTPDSCHRECEIVERLLRSCALINGCONVENTION Enforce one explicit LLR sign rule.

setup6GRSimToolkit("Verbose", false);
fixture = StrictPDSCHChainFixture.create(1);
tx = sixgr.pdsch.PDSCHTransmitter( ...
    fixture.TransportBlocks,fixture.Assignment,fixture.ResourcePlan, ...
    fixture.Carrier,fixture.ReferenceConfig, ...
    "PrecoderBundle",fixture.PrecoderBundle);
rx = sixgr.pdsch.PDSCHReceiver( ...
    tx.Waveform,fixture.Assignment,fixture.ResourcePlan,fixture.Carrier, ...
    fixture.ReferenceConfig,fixture.ReceiverConfig, ...
    "CodingPlans",tx.CodingPlans, ...
    "PrecoderBundle",fixture.PrecoderBundle);
hardScrambled = int8(rx.ScrambledLLR{1} < 0);
roundTrip = sixgr.pdsch.PDSCHModulator( ...
    rx.CodewordSymbols{1},"QPSK","Operation","hard-demap");
assert(isequal(hardScrambled,roundTrip) ...
    && string(rx.DemodulationInfo{1}.LLRConvention) ...
    == "positive_favours_bit_zero", ...
    "Strict soft demapper LLR sign convention is inconsistent.");

wrong = fixture.ReceiverConfig;
wrong.LLRConvention = "negative_favours_bit_zero";
localAssertIdentifier(@() sixgr.pdsch.PDSCHReceiver( ...
    tx.Waveform,fixture.Assignment,fixture.ResourcePlan,fixture.Carrier, ...
    fixture.ReferenceConfig,wrong, ...
    "CodingPlans",tx.CodingPlans, ...
    "PrecoderBundle",fixture.PrecoderBundle), ...
    "sixgr:pdsch:PDSCHReceiver:UnsupportedLLRConvention");
fprintf("PDSCH strict RX LLR convention: sign and typed guard pass\n");
ok = true;
end

function localAssertIdentifier(fn,identifier)
try
    fn();
catch cause
    assert(string(cause.identifier) == string(identifier), ...
        "Observed %s, expected %s.",cause.identifier,identifier);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.",identifier);
end
