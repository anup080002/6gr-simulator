function ok = testPDSCHPairCoverageProof()
%TESTPDSCHPAIRCOVERAGEPROOF Prove independent feasible-domain pair coverage.

setup6GRSimToolkit("Verbose",false,"RunToolboxChecks",false);
vectorRoot = fullfile(fileparts(mfilename("fullpath")),"vectors","pdsch");

proof = sixgr.pdsch.PDSCHStudyCoverageExecutor.pairCoverageProof(vectorRoot);
assert(proof.RequiredPairCount > 0 ...
    && proof.GeneratedCaseCount >= 40 ...
    && proof.CoveredPairCount == proof.RequiredPairCount ...
    && proof.MissingPairCount == 0 ...
    && strlength(proof.PairCoverageSHA256) == 64, ...
    "Generated feasible-domain design did not prove exact pair coverage.");
assert(string(proof.PairUniverseDefinition) == ...
    "independently_enumerated_feasible_pairs_over_mandatory_domains_with_dmrs_rank_constraints", ...
    "Pair-universe semantics must be explicit and constrained.");

identifier = "";
try
    sixgr.pdsch.PDSCHStudyCoverageExecutor.pairCoverageProof( ...
        vectorRoot,"SelectedCaseCount",15);
catch ME
    identifier = string(ME.identifier);
end
assert(identifier == ...
    "sixgr:pdsch:PDSCHCoverageExecutor:PairCoverageIncomplete", ...
    "An incomplete first-N selection must fail with the typed pair error.");

fprintf("PDSCH feasible-pair proof: %d/%d, SHA-256 %s\n", ...
    proof.CoveredPairCount,proof.RequiredPairCount, ...
    proof.PairCoverageSHA256);
ok = true;
end
