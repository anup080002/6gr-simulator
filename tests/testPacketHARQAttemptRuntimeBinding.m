function ok=testPacketHARQAttemptRuntimeBinding()
% Existing production refresh must update pending metadata-only packets.
% This tests the real call site, not only the new standalone reducer.
setup6GRSimToolkit('Verbose',false);
p=struct('Direction',"DL",'UEIndex',1,'RNTI',1001,'PacketId',"packet", ...
    'ApplicationPacketId',"app",'OfferedBits',1000,'ScheduledBits',400, ...
    'RemainingBits',600,'DeliveredBits',0,'DeliverySuccess',false,'HARQAttemptCount',0);
s=struct('Direction',"DL",'UEIndex',1,'RNTI',1001,'PacketId',"packet", ...
    'ApplicationPacketId',"app",'TransportBlockId',"TB", ...
    'HARQProcessId',0,'NDIEpoch',1,'ScheduleSlot',1,'SegmentIndex',1, ...
    'PayloadBits',400,'HARQAttemptCount',0,'DeliverySuccess',false);
h=struct('Direction',"DL",'UEIndex',1,'RNTI',1001,'HarqID',0, ...
    'NDIEpoch',1,'TBId',"TB",'PHYGrantContextId',"actual-attempt-1", ...
    'Slot',1,'CombinedDecodeOK',false,'SweepPointIndex',1);
state=struct('ProtocolWaveformEnabled',false, ...
    'PacketDeliveryLedgerTable',struct2table(p), ...
    'PacketSDULedgerTable',struct2table(s),'HARQTimelineTable',struct2table(h));
state=sixgr.truth.refreshApplicationPacketDeliveries(state);
assert(state.PacketDeliveryLedgerTable.HARQAttemptCount==1 && ...
    state.PacketSDULedgerTable.HARQAttemptCount==1, ...
    'sixgr:test:PacketAttemptRuntimeNotReconciled', ...
    'Pending metadata-only packet counts must follow the actual receiver timeline.');
assert(state.PacketDeliveryLedgerTable.DeliveredBits==0 && ...
    ~state.PacketDeliveryLedgerTable.DeliverySuccess, ...
    'Do not convert a HARQ attempt into application-byte delivery.');
assert(state.PacketDeliveryLedgerTable.UnscheduledBits==600 && ...
    state.PacketDeliveryLedgerTable.UnresolvedReservedBits==400 && ...
    state.PacketDeliveryLedgerTable.CompletedApplicationBits==0 && ...
    state.PacketDeliveryLedgerTable.BitConservationErrorBits==0, ...
    'This fixture has no actual TX lifecycle: do not invent its terminal state.');
ok=true;
end
