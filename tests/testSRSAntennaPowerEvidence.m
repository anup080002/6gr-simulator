function ok=testSRSAntennaPowerEvidence()
% Actual native SRS IQ with DECLARED physical-receipt boundary fixtures.
% No shared RF/channel owner, access procedure or accuracy campaign runs.
% The separate test20MHzSharedSRSPowerBinding exercises original shared IQ.
setup6GRSimToolkit('Verbose',false);
for bandwidth=[24 52]
    [carrier,srs,pre,replay,resource,plane,expectedW]=fixture(bandwidth,1);
    out=sixgr.phy.srs.measureSRSAntennaPower(carrier,srs,pre,replay,[0 0],resource,plane);
    assert(out.SRSAbsolutePowerAvailable, ...
        'test:SRSAntennaPower:Unavailable','%s: %s',out.SRSAbsolutePowerStatus,out.SRSAbsolutePowerErrorIdentifier);
    evidence=jsondecode(out.SRSAbsolutePowerEvidenceJSON);
    assert(string(evidence.ReferencePlane)=="internal_physical_receive_element_before_RX_front_end" && ...
        string(evidence.ReferencePointApplicability)== ...
        "internal_element_measurement_not_standardized_1O_or_2O_UL_SRS_RSRP_qualification", ...
        'Internal element samples must not be relabelled as conducted connectors or qualified 1-O branch power.');
    measuredW=10.^((out.SRSRSRPPerReceiveAntenna_dBm-30)/10);
    assert(norm(measuredW-expectedW)<=1e-9*norm(expectedW), ...
        'test:SRSAntennaPower:Scale','Actual native SRS RE power must preserve FFT/amplitude normalization.');
    assert(out.SRS_RSRP_dBm==max(out.SRSRSRPPerReceiveAntenna_dBm) && ...
        out.SRSAbsolutePowerSelectedBranch0==0 && ...
        out.SRS_RSRP_dBm>out.SRSAbsolutePowerBranchMean_dBm && ...
        abs(out.SRSAbsolutePowerBranchMean_dBm-(10*log10(mean(expectedW))+30))<1e-9);
    assert(isequal(evidence.ObservationSHA256,char(pre.sampleHash())) && ...
        evidence.Resource.ResourceID==17 && evidence.SRSNumPorts==2 && ...
        evidence.UniquePhysicalRECount>0 && ...
        ~evidence.PostRFEstimateConsumed && ~evidence.TruthChannelConsumed && ...
        ~evidence.ReceiverFeedbackInput && ~out.SRSAbsolutePowerAccuracyQualified);
    assert(evidence.FFTSupportAvailable && ...
        string(evidence.FFTSupport.AlignedWaveformSHA256)==string(evidence.AlignedWaveformSHA256) && ...
        string(evidence.FFTSupport.GridSHA256)==string(evidence.ReceivedGridSHA256) && ...
        evidence.FFTSupport.ObservationStartSample==pre.StartSample && ...
        evidence.FFTSupport.ObservationEndSampleExclusive==pre.EndSampleExclusive && ...
        evidence.FFTSupport.SampleRateHz==pre.SampleRateHz);
    assert(string(sixgr.rrc.asn1.asn1SHA256Hex(unicode2native( ...
        char(out.SRSAbsolutePowerEvidenceJSON),'UTF-8')))==out.SRSAbsolutePowerEvidenceSHA256);
    [~,~,scaled,scaledReplay,scaledResource,scaledPlane]=fixture(bandwidth,2);
    scaledOut=sixgr.phy.srs.measureSRSAntennaPower( ...
        carrier,srs,scaled,scaledReplay,[0 0],scaledResource,scaledPlane);
    assert(scaledOut.SRSAbsolutePowerAvailable && ...
        abs(scaledOut.SRS_RSRP_dBm-out.SRS_RSRP_dBm-20*log10(2))<1e-9);
end
% A changed post-front-end observation changes practical Hest, not the
% independent antenna-plane measurement. No inverse gain compensation.
cfg=sixgr.config.defaultConfig(); cfg.phy.srs.runtimeChannelEstimator='nr_channel_estimate';
rxSamples=pre.readComplete();
args={'Carrier',carrier,'SRS',srs,'NoiseVar',1e-12,'NoiseVarDomain','grid', ...
    'StrictNoiseVarianceRequired',false,'TimingSearchWindowSamples',[0 0], ...
    'ReceivedExecutionEvidence',replay,'AntennaMeasurementObservation',pre, ...
    'AntennaMeasurementEvidence',plane,'AntennaMeasurementResource',resource};
a=sixgr.phy.ul.SRS_Rx(rxSamples,cfg,args{:});
b=sixgr.phy.ul.SRS_Rx(rxSamples*4,cfg,args{:});
assert(a.SRSAbsolutePowerAvailable && b.SRS_RSRP_dBm==a.SRS_RSRP_dBm && ...
    b.SRSAbsolutePowerEvidenceSHA256==a.SRSAbsolutePowerEvidenceSHA256 && ...
    norm(double(b.Hest(:))-4*double(a.Hest(:)))<1e-9*norm(double(b.Hest(:))));
bad=replay; bad.WaveformAmplitudeUnit="normalized_complex_baseband";
unavailable(carrier,srs,pre,bad,resource,plane,"not_available_nonabsolute_executed_sample_unit","");
bad=replay; bad.RuntimeChannelStartSample=pre.StartSample+1;
unavailable(carrier,srs,pre,bad,resource,plane,"not_available_antenna_measurement_failed", ...
    "sixgr:srs:AntennaPowerIdentity");
bad=replay; bad.ReceiverID="gnb_2_rx";
unavailable(carrier,srs,pre,bad,resource,plane,"not_available_antenna_measurement_failed", ...
    "sixgr:srs:AntennaPowerPlane");
badPlane=plane; badPlane.ReceiverID="gnb_1_rx:post_rf";
unavailable(carrier,srs,pre,replay,resource,badPlane,"not_available_antenna_measurement_failed", ...
    "sixgr:srs:AntennaPowerPlane");
replacement=buffer(rxSamples*4,pre.StartSample,pre.SampleRateHz);
unavailable(carrier,srs,replacement,replay,resource,plane,"not_available_antenna_measurement_failed", ...
    "sixgr:srs:AntennaPowerPlane");
bad=replay; bad.ReceiveStreamExecutionSegments{1}.EndSampleExclusive=pre.EndSampleExclusive-1;
unavailable(carrier,srs,pre,bad,resource,plane,"not_available_antenna_measurement_failed", ...
    "sixgr:srs:AntennaPowerCoverage");
bad=replay; bad.ReceiveStreamExecutionSegments{1}.Execution.SampleRateHz=pre.SampleRateHz*2;
unavailable(carrier,srs,pre,bad,resource,plane,"not_available_antenna_measurement_failed", ...
    "sixgr:srs:AntennaPowerExecution");
bad=replay; first=bad.ReceiveStreamExecutionSegments{1}; second=first;
middle=pre.StartSample+floor((pre.EndSampleExclusive-pre.StartSample)/2);
first.EndSampleExclusive=middle; second.StartSample=middle;
second.Execution.ConfigurationEpoch=first.Execution.ConfigurationEpoch+1;
bad.ReceiveStreamExecutionSegments={first;second};
unavailable(carrier,srs,pre,bad,resource,plane,"not_available_antenna_measurement_failed", ...
    "sixgr:srs:AntennaPowerEpoch");
silent=buffer(zeros(size(rxSamples),'like',rxSamples),pre.StartSample,pre.SampleRateHz);
silentPlane=plane; silentPlane.Observation=silent;
unavailable(carrier,srs,silent,replay,resource,silentPlane,"not_available_antenna_measurement_failed", ...
    "sixgr:phy:sync:ULReferenceTimingUnavailable");
missing=sixgr.phy.srs.measureSRSAntennaPower();
assert(~missing.SRSAbsolutePowerAvailable && isnan(missing.SRS_RSRP_dBm));
badResource=resource; badResource.ConfigHash="";
unavailable(carrier,srs,pre,replay,badResource,plane,"not_available_antenna_measurement_failed", ...
    "sixgr:srs:AntennaPowerResource");
% Failure of this optional independent measurement does not poison usable
% practical channel estimation. It is still NOT absolute-power acceptance.
badArgs=args; badArgs{2*find(strcmp(args(1:2:end),'AntennaMeasurementEvidence'))}=badPlane;
c=sixgr.phy.ul.SRS_Rx(rxSamples,cfg,badArgs{:});
assert(isequaln(c.Hest,a.Hest) && c.MeasurementUsable==a.MeasurementUsable && ...
    ~c.SRSAbsolutePowerAvailable && isnan(c.SRS_RSRP_dBm));
% Production row normalization retains every compact power provenance field.
row=sixgr.truth.makeLinkTrialRow(cfg,"UL",0,1);
for name=setdiff(string(fieldnames(out)),"SRSRSRPPerReceiveAntenna_dBm").'
    row.(name)=out.(name);
end
row.SRSRSRPPerReceiveAntenna_dBm=string(jsonencode(out.SRSRSRPPerReceiveAntenna_dBm));
tableIn=struct2table(row,'AsArray',true);
tableOut=sixgr.truth.SharedDataCompletionRuntime.ensureLinkTrialTable(tableIn,"UL",0,cfg);
folder=tempname; mkdir(folder); path=fullfile(folder,'srs_antenna_power.csv');
% Exercise the same lossless SRS publication owner as shared runtime. The
% default writetable decimal formatting is not exact binary64 round-trip.
sixgr.truth.writeOptionalRuntimeFeatureTable(cfg,"srs",string(path),tableOut, ...
    'PreserveSchema',true);
roundtrip=sixgr.util.csvReadTable(path);
for name=string(fieldnames(out)).'
    assert(ismember(name,string(tableOut.Properties.VariableNames)) && ...
        ismember(name,string(roundtrip.Properties.VariableNames)));
end
assert(roundtrip.SRS_RSRP_dBm==out.SRS_RSRP_dBm && ...
    string(roundtrip.SRSAbsolutePowerEvidenceJSON)==out.SRSAbsolutePowerEvidenceJSON && ...
    string(roundtrip.SRSAbsolutePowerEvidenceSHA256)==out.SRSAbsolutePowerEvidenceSHA256);
fprintf('SRS_ANTENNA_POWER_COMPONENT_PASS csv=%s\n',path); ok=true;
end

function unavailable(carrier,srs,pre,replay,resource,plane,status,identifier)
out=sixgr.phy.srs.measureSRSAntennaPower(carrier,srs,pre,replay,[0 0],resource,plane);
assert(~out.SRSAbsolutePowerAvailable && isnan(out.SRS_RSRP_dBm) && ...
    out.SRSAbsolutePowerStatus==status && out.SRSAbsolutePowerErrorIdentifier==identifier && ...
    out.SRSAbsolutePowerEvidenceJSON=="" && out.SRSAbsolutePowerEvidenceSHA256=="");
end

function [carrier,srs,pre,replay,resource,plane,expectedW]=fixture(nrb,amplitude)
carrier=nrCarrierConfig('NSizeGrid',nrb,'SubcarrierSpacing',30,'NCellID',41);
srs=nrSRSConfig('NumSRSPorts',2,'NumSRSSymbols',2,'SymbolStart',12, ...
    'Repetition',2,'KTC',2,'CSRS',0,'BSRS',0,'BHop',0,'SRSPeriod','on');
indices=nrSRSIndices(carrier,srs); symbols=nrSRS(carrier,srs);
grid=nrResourceGrid(carrier,2); grid(indices)=symbols;
% Fixed declared channel, unequal branches, no injected estimation oracle.
H=[1 .125; .3i .0625i];
received=reshape(reshape(grid,[],2)*H,size(grid))*amplitude;
[wave,info]=nrOFDMModulate(carrier,received,'Windowing',0);
pre=buffer(wave,10000,info.SampleRate);
[k,l,~]=ind2sub(size(grid),double(indices(:)));
support=unique(sub2ind([size(grid,1),size(grid,2)],k,l));
flat=reshape(received,[],2);
expectedW=mean(abs(flat(support,:)).^2,1)/(info.Nfft^2*1000);
execution=struct('Source','composed_tx_retained_rf_per_link_channel_sum_receiver_noise_rf', ...
    'ApproximationMode','none','StartSample',pre.StartSample, ...
    'EndSampleExclusive',pre.EndSampleExclusive,'SampleRateHz',pre.SampleRateHz, ...
    'ConfigurationEpoch',7,'RX',struct('ID','gnb_1_rx', ...
    'Replay',struct('WaveformAmplitudeUnit','sqrt_mW')));
segment=struct('StartSample',pre.StartSample,'EndSampleExclusive',pre.EndSampleExclusive, ...
    'Execution',execution);
replay=struct('ReceiverID','gnb_1_rx','RuntimeChannelStartSample',pre.StartSample, ...
    'RuntimeChannelEndSample',pre.EndSampleExclusive,'WaveformAmplitudeUnit','sqrt_mW', ...
    'ReceiveStreamExecutionSegments',{{segment}},'CompositeReceiverFrontEndApplied',true);
resource=struct('ResourceID',17,'ConfigHash',"declared_native_SRS_component_fixture", ...
    'Scope',"declared_receipt_not_shared_physical_owner");
plane=struct('ReceiverID','gnb_1_rx:pre_rf','ObservationID','declared_srs_17', ...
    'Observation',pre);
end

function out=buffer(samples,first,fs)
out=sixgr.phy.waveform.WaveformObservationBuffer(first,first+size(samples,1),fs,size(samples,2));
out.append(sixgr.phy.waveform.WaveformChunk(samples,first),fs);
end
