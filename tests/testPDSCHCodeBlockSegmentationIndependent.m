function ok = testPDSCHCodeBlockSegmentationIndependent()
%TESTPDSCHCODEBLOCKSEGMENTATIONINDEPENDENT Compare plan with scalar oracle.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
cases = [ ...
    struct("A",24,    "R",0.50), ...
    struct("A",192,   "R",0.50), ...
    struct("A",193,   "R",0.50), ...
    struct("A",292,   "R",0.50), ...
    struct("A",293,   "R",0.50), ...
    struct("A",3824,  "R",0.50), ...
    struct("A",3825,  "R",0.50), ...
    struct("A",8424,  "R",0.50), ...
    struct("A",8425,  "R",0.50), ...
    struct("A",10000, "R",0.50), ...
    struct("A",20000, "R",0.50)];

multiCBCount = 0;
fillerCaseCount = 0;
for i = 1:numel(cases)
    cfg = cases(i);
    oracle = sixgr.pdsch.oracle.LDPCSegmentationSpec(cfg.A, cfg.R);
    G = 2 * ceil((oracle.MotherCodeLength * oracle.NumCodeBlocks) / 2);
    plan = sixgr.pdsch.DLSCHCodingPlan.resolve( ...
        "TransportBlockSize", cfg.A, ...
        "TargetCodeRate", cfg.R, ...
        "RateMatchedBitCount", G, ...
        "RV", 0, ...
        "Modulation", "QPSK", ...
        "NumLayers", 1);

    assert(double(plan.BaseGraph) == oracle.BaseGraph, "A=%d BG mismatch.", cfg.A);
    assert(double(plan.TBCRCLength) == oracle.TBCRCLength, ...
        "A=%d TB CRC length mismatch.", cfg.A);
    assert(double(plan.TransportBlockLengthWithCRC) == oracle.B, ...
        "A=%d B mismatch.", cfg.A);
    assert(double(plan.NumCodeBlocks) == oracle.NumCodeBlocks, ...
        "A=%d C mismatch.", cfg.A);
    assert(double(plan.CBCRCLength) == oracle.CBCRCLength, ...
        "A=%d CB CRC length mismatch.", cfg.A);
    assert(double(plan.LiftingSize) == oracle.LiftingSize, ...
        "A=%d Zc mismatch.", cfg.A);
    assert(double(plan.LiftingSetIndex) == oracle.LiftingSetIndex, ...
        "A=%d lifting-set index mismatch.", cfg.A);
    assert(double(plan.CodeBlockLength) == oracle.CodeBlockLength, ...
        "A=%d K mismatch.", cfg.A);
    assert(double(plan.MotherCodeLength) == oracle.MotherCodeLength, ...
        "A=%d N mismatch.", cfg.A);
    assert(double(plan.FillerCount) == oracle.FillerCount, ...
        "A=%d filler-count mismatch.", cfg.A);
    for c = 1:oracle.NumCodeBlocks
        assert(isequal(plan.FillerPositionsZeroBased{c}(:), ...
            oracle.FillerPositionsZeroBased{c}(:)), ...
            "A=%d CB=%d filler-position mismatch.", cfg.A, c - 1);
    end
    multiCBCount = multiCBCount + (oracle.NumCodeBlocks > 1);
    fillerCaseCount = fillerCaseCount + (oracle.FillerCount > 0);
end

assert(multiCBCount >= 3 && fillerCaseCount >= 8, ...
    "Segmentation suite did not exercise required CB/filler cases.");
fprintf(['PDSCH segmentation: %d independent boundary cases, multi-CB=%d, ' ...
    'with-filler=%d; mismatches=0\n'], numel(cases), multiCBCount, fillerCaseCount);
ok = true;
end
