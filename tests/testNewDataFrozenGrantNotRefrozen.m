function ok = testNewDataFrozenGrantNotRefrozen()
%TESTNEWDATAFROZENGRANTNOTREFROZEN Preserve scheduler spatial authority.

setup6GRSimToolkit("Verbose", false);
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile(pwd, ...
    "simulator", "configs", "scenarios", ...
    "webgui_sinr_sweep_64x4_mu_mimo_repair_slice.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scenario, tempdir);

% Four configured RF chains feed four logical ports.  A scheduled rank-two
% user receives its own 4x2 logical baseband matrix and exact 64x2 physical
% precoder, while the frozen hardware architecture remains 64x4.
F = complex(zeros(64, 4));
for port = 1:4
    rows = (port-1)*16 + (1:16);
    F(rows, port) = exp(1j * 2*pi*(0:15).' * (port-1) / 16) / 4;
end
% One scheduled UE owns unit total precoder power across both layers.
% Four coefficients of magnitude 1/2 give ||W||_F^2 = 1.
W = [1 0; 0 1; 1 0; 0 1] / 2;
P = F * W;
cfgFreeze = cfg;
cfgFreeze.phy.pdsch.hybridElementToPortMatrix = F;
cfgFreeze.phy.pdsch.numPorts = 4;
cfgFreeze.phy.pdsch.nPorts = 4;
cfgFreeze.phy.pdsch.numRFChains = 4;

grant = struct( ...
    "Direction", "DL", "Frame", 1, "Slot", 6, ...
    "RNTI", 3, "UEIndex", 3, "ServingCell", 1, ...
    "PRBSet", 0:11, "SymbolAllocation", [2 12], ...
    "Modulation", "QPSK", "MCSIndex", 1, ...
    "TargetCodeRate", 0.1884765625, ...
    "NumLayers", 2, "Layers", 2, ...
    "NumLogicalPorts", 4, "NumRFChains", 4, ...
    "PrecodingMatrixLogicalPorts", W, ...
    "PrecodingMatrix", P, ...
    "HybridElementToPortMatrix", F, ...
    "TBSBits", NaN, "TBSBytes", NaN, ...
    "TransportBlockSize", NaN, ...
    "IsRetransmission", false, ...
    "HARQ", struct("IsRetransmission", false, "NDI", true,"HarqID",0,"RV",0), ...
    "ExactPHYFeasibilityChecked", false, ...
    "ExactPHYFeasible", false, ...
    "ControlAbsoluteSlot",5, ...
    "ControlDecodeOk", false, ...
    "PDCCHGrantBindingOk", false, ...
    "GrantContextId", "phase19-slot6-new-data-regression");

% Derive the fixture TBS from the exact materialized allocation.  A stale
% hand-entered TBS would test a contradiction rather than frozen spatial
% authority and is therefore forbidden even in a regression fixture.
scheduler=sixgr.l2.mac.SchedulerPF(cfgFreeze,'Direction','DL');
grant=scheduler.attachCanonicalTimingDecision(grant);
grant.Slot=grant.ScheduledAbsoluteSlot+1;
cfgFreeze=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfgFreeze,grant.Slot);
carrier = sixgr.phy.grid.makeCarrier(cfgFreeze);
[pdschInd, pdschInfo, pdsch] = sixgr.phy.grid.allocREsPDSCH( ...
    carrier, cfgFreeze, "PRBSet", grant.PRBSet, ...
    "SymbolAllocation", grant.SymbolAllocation, ...
    "NumLayers", grant.NumLayers, "Modulation", grant.Modulation, ...
    "RNTI", grant.RNTI, "NID", carrier.NCellID, ...
    "MappingType", cfgFreeze.phy.pdsch.mappingType);
xOverhead = sixgr.phy.dl.resolvePDSCHXOverhead( ...
    cfgFreeze, grant.SymbolAllocation);
accounting = sixgr.phy.resource.computeResourceAccounting( ...
    "PDSCH", carrier, pdsch, "ChannelIndices", pdschInd, ...
    "AllocationInfo", pdschInfo, "IndexBase", "1based", ...
    "TargetCodeRate", grant.TargetCodeRate, ...
    "XOverhead", xOverhead);
grant.TBSBits = double(nrTBS(pdsch.Modulation, pdsch.NumLayers, ...
    numel(pdsch.PRBSet), accounting.NREPerPRBForTBS, ...
    grant.TargetCodeRate, xOverhead));
grant.TBSBytes = grant.TBSBits / 8;
grant.TransportBlockSize = grant.TBSBits;
grant.NREPerPRB = accounting.NREPerPRBForTBS;
grant.ExactPHYFeasibilityChecked = true;
grant.ExactPHYFeasible = true;
grant.DCI=scheduler.buildDCIBitfield(grant);
% Decode actual encoded PDCCH samples through a declared ideal loopback.
% This is a control-codec fixture, not access or shared fading evidence.
grant=localReceiveControl(cfgFreeze,grant);
phyGrant = sixgr.phy.grant.freezePHYGrant(cfgFreeze, "DL", grant, ...
    "SNR_dB", 20, "Frame", 1, "Slot", grant.Slot);
tbsBits = double(phyGrant.CodingLayout.TBSBits);
tb = zeros(tbsBits, 1, "int8");
grant.TBSBits = tbsBits;
grant.TBSBytes = floor(tbsBits/8);
grant.TransportBlockSize = tbsBits;
grant.ScheduledTransportBlockSize = tbsBits;
grant.HARQTBContext = struct("TBSBits", tbsBits, "NDI", true, ...
    "OriginalNumLayers", 2);
grant.PHYGrant = phyGrant;

% Reproduce the transient per-user mirror that killed Phase-19 slot 6: it
% contains this user's 64x2 selected beam, not the shared 64x4 RF matrix.
% New-data execution must consume the already frozen PHYGrant and must not
% refreeze from this stale mirror.
cfgExecute = cfg;
cfgExecute.phy.pdsch.hybridElementToPortMatrix = P;
out = sixgr.link.runDLPDSCHThroughput(cfgExecute, ...
    "NumFrames", 1, "SNR_dB", 20, ...
    "StartFrameIndex", 1, "StartSlotIndex", grant.Slot, ...
    "GrantSnapshot", grant, "PHYGrant", phyGrant, ...
    "TransportBlockBits", tb);
assert(istable(out.TrialTable) && height(out.TrialTable) == 1, ...
    "The frozen new-data grant must reach one production waveform trial.");
assert(double(out.TrialTable.Layers(1)) == 2 && ...
    logical(out.TrialTable.HybridElementDomainApplied(1)) && ...
    double(out.TrialTable.PhysicalTxAntennas(1)) == 64 && ...
    double(out.TrialTable.TxWaveformColumns(1)) == 64, ...
    "The executed trial must preserve rank two, four RF chains and 64 physical columns.");

% A HARQ retransmission is refrozen to bind current-slot control, but its
% first-transmission RF architecture remains authoritative.  Reproduce the
% full-run failure using the same stale 64x2 per-user cfg against the frozen
% 64x4 grant.
replayGrant = grant;
replayGrant.IsRetransmission = true;
replayGrant.HARQ.IsRetransmission = true;
replayState = struct("CurrentFrame", 2, "CurrentSlot", 41);
replayHARQ = struct("HarqID", 0, "HARQProcess", 0, "NDI", true, ...
    "NDIEpoch", 1, "RV", 2, "IsRetransmission", true, ...
    "TransportBlockContext", grant.HARQTBContext);
refrozen = sixgr.truth.CoupledTruthRuntime. ...
    refreezeReplayGrantPHYContractRuntime( ...
    cfgExecute, replayGrant, "DL", replayState, replayHARQ);
assert(isequal(size(refrozen.PHYGrant.PrecodingState.HybridElementToPortMatrix), ...
    [64 4]) && ...
    isequal(refrozen.PHYGrant.PrecodingState.HybridElementToPortMatrix, F) && ...
    double(refrozen.PHYGrant.AntennaArchitecture.NumRFChains) == 4 && ...
    double(refrozen.PHYGrant.AntennaArchitecture.NumLogicalPorts) == 4, ...
    "HARQ refreeze must restore the exact frozen 64x4 RF architecture before replay.");
ok = true;
end

function grant=localReceiveControl(cfg,grant)
controlCfg=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,grant.ControlAbsoluteSlot+1);
p=sixgr.link.preparePDCCHTransmission(controlCfg,'Grant',grant, ...
    'RNTI',grant.RNTI,'K',numel(grant.DCI.Bits));
[rx,~]=sixgr.phy.dl.PDCCH_Rx(p.TransmitSamples,controlCfg, ...
    'Carrier',p.Tx.Carrier,'PDCCH',p.Tx.PDCCH,'RNTI',grant.RNTI, ...
    'K',numel(grant.DCI.Bits),'ExpectedDCIBits',grant.DCI.Bits,'SampleRate_Hz',p.SampleRateHz);
decoded=sixgr.phy.pdcch.decodeDCIPayload(rx.DCIBits,grant.DCI.Format,grant.DCI.ContextData);
authored=sixgr.phy.pdcch.decodeDCIPayload(grant.DCI.Bits,grant.DCI.Format,grant.DCI.ContextData);
assert(rx.Ok && rx.CausalGrantDecodeOk && isequal(rx.DCIBits(:),grant.DCI.Bits(:)) && ...
    isequaln(decoded.Fields,authored.Fields),'The loopback must decode the exact scheduled DCI.');
grant.ControlDecodeOk=logical(rx.CausalGrantDecodeOk);
grant.PDCCHGrantBindingOk=logical(rx.CausalGrantDecodeOk);
grant.PDCCHGrantDCIId=decoded.PayloadHash;
grant.PDCCHGrantDCIFormat=decoded.Format;
grant.PDCCHGrantDCIFieldsHash=sixgr.util.sha256Hex(uint8(unicode2native( ...
    jsonencode(orderfields(decoded.Fields)),'UTF-8')));
grant.PDCCHGrantFieldsHash=sixgr.util.sha256Hex(uint8(unicode2native( ...
    jsonencode(orderfields(authored.Fields)),'UTF-8')));
end
