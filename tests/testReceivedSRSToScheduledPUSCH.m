function ok=testReceivedSRSToScheduledPUSCH()
% Actual shared SRS -> accepted spatial feedback -> normal future-UL planner
% -> joint control admission -> independently received PDCCH -> deferred UE
% preparation -> emitted/completed PUSCH, canonical completion/publication
% and the exact per-UE link-adaptation state drain.
% The shared prefix retains real PBCH/SRS/TRS gate delivery and CSI/PUCCH
% coexistence. Initial connected context and TAG remain declared component
% inputs; this is not random access, n40, all-rank, BLER or natural scheduled
% HARQ-retry qualification. No accepted DCI or later grant is test-authored.
%
% The optional nineteenth harness argument leaves every baseline assertion
% intact and adds one normally planned UL application on the same live owner.
setup6GRSimToolkit('Verbose',false);
assert(nargin('testSharedPUSCHChannelArtifacts')>=19, ...
    'test:SharedSRSContinuationNotIntegrated', ...
    'The normal-UL shared harness continuation has not been integrated yet.');
root=fileparts(fileparts(mfilename('fullpath')));
fixture=fullfile(root,'simulator','configs','scenarios', ...
    'lls_tdd_received_csi_application_coexistence_fixture.yaml');
folder=fullfile(root,'logs','received_srs_to_scheduled_pusch');
if ~isfolder(folder), mkdir(folder); end
[ok,state]=testSharedPUSCHChannelArtifacts('TDD',false,false,true,true,true,false, ...
    tempname(folder),fixture,false,true,false,false,true,2,false,false,false,true);
assert(ok && state.TestSRSContinuationCompleted && state.TestPUSCHReceived, ...
    'test:SharedSRSContinuationNotCompleted', ...
    'Scheduling intent or a received control alone is not a completed UL application.');
assert(state.TestSRSContinuationApplication.WaveformApplicationVerified && ...
    ~state.TestSRSContinuationApplication.FullScenarioQualified && ...
    ~state.TestSRSContinuationApplication.NaturalSchedulerRetryQualified);
assert(state.TestCanonicalCompletionDrainVerified && ...
    height(state.TestPublishedULTrials)==1 && isempty(state.TestPublishedDLTrials) && ...
    isempty(state.SharedCompletedDataPlans) && ...
    isequaln(state.SharedULLinkAdaptationStates,state.TestPublishedULStates), ...
    'The physical continuation must publish the canonical finalized row and drain its actual LA output.');
end
