function test6GTopLevelSchemaSections()
%TEST6GTOPLEVELSCHEMASECTIONS Verify required 6G top-level sections exist and representative aliases resolve.

repoRoot = fileparts(fileparts(mfilename("fullpath")));
baselinePath = fullfile(repoRoot, "simulator", "configs", "scenarios", "dl_4ghz_baseline.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(baselinePath);
s = scfg.toStruct();

requiredSections = [ ...
    "meta","run_control","config_inheritance","output_control","global_radio_scope","frame_timing", ...
    "bandwidth_operation","deployment_topology","mobility","antenna_and_array","power_and_rf_frontend", ...
    "waveform","resource_grid","channel_model","interference","signals_and_channels_common","reference_signals", ...
    "pdcch","pdsch","pusch","pucch","prach","mimo_and_beam_management","csi_acquisition_and_reporting", ...
    "channel_coding","modulation_and_mapping","link_adaptation","harq","synchronization_and_tracking", ...
    "receiver_algorithms","impairments","ai_ml","energy_and_complexity","kpi_spec","sweeps_and_matrix","sanity_checks", ...
    "processing_chains" ...
    ];

for i = 1:numel(requiredSections)
    assert(isfield(s, requiredSections(i)), ...
        "sixgr:test:6GTopLevel:MissingSection", ...
        "Resolved scenario is missing required top-level section '%s'.", requiredSections(i));
end

assert(isfield(s.signals_and_channels_common, "ssb"), ...
    "sixgr:test:6GTopLevel:MissingCommonSignalObject", ...
    "signals_and_channels_common.ssb must exist.");
assert(isfield(s.reference_signals, "pdsch_dmrs"), ...
    "sixgr:test:6GTopLevel:MissingReferenceSignalObject", ...
    "reference_signals.pdsch_dmrs must exist.");

tmp = fullfile(tempdir, "sixgr_top_level_alias_smoke.json");
cfg = struct();
cfg.inherits = {"simulator/configs/defaults/global.yaml"};
cfg.meta = struct("scenario_id", "top_level_alias_smoke");
cfg.run_control = struct("seed", 99, "deterministic_mode", true);
cfg.global_radio_scope = struct("carrier_frequency_hz", 7e9, "frequency_range_label", "FR1");
cfg.channel_model = struct("model_family", "CDL", "scenario_label", "CDL-D");
cfg.pdcch = struct("enabled", false);
cfg.mimo_and_beam_management = struct("rank_set", [2]);
txt = jsonencode(cfg, "PrettyPrint", true);
fid = fopen(tmp, "w");
cleanup = onCleanup(@() localDeleteFile(tmp, fid));
assert(fid >= 0, "sixgr:test:6GTopLevel:TempWriteFailed", "Unable to create temp config '%s'.", tmp);
fwrite(fid, txt, "char");
fclose(fid);

smokeCfg = sixgr.lls6g.config.loadScenarioConfig(tmp);
resolved = smokeCfg.toStruct();
assert(resolved.simulation.random_seed == 99, ...
    "sixgr:test:6GTopLevel:RunControlAlias", ...
    "run_control.seed must map to simulation.random_seed.");
assert(resolved.frequency.center_frequency_hz == 7e9, ...
    "sixgr:test:6GTopLevel:RadioAlias", ...
    "global_radio_scope.carrier_frequency_hz must map to frequency.center_frequency_hz.");
assert(strcmpi(string(resolved.channels.model_type), "CDL"), ...
    "sixgr:test:6GTopLevel:ChannelAlias", ...
    "channel_model.model_family must map to channels.model_type.");
assert(strcmpi(string(resolved.channels.profile), "CDL-D"), ...
    "sixgr:test:6GTopLevel:ProfileAlias", ...
    "channel_model.scenario_label must map to channels.profile.");
assert(~logical(resolved.control.pdcch_enabled), ...
    "sixgr:test:6GTopLevel:PDCCHAlias", ...
    "pdcch.enabled must map to control.pdcch_enabled.");
rankVal = sixgr.util.structGet(resolved, "mimo.n_layers", NaN);
assert(rankVal == 2, ...
    "sixgr:test:6GTopLevel:RankAlias", ...
    "mimo_and_beam_management.rank_set must map to mimo.n_layers.");
end

function localDeleteFile(path, fid)
if nargin >= 2 && fid > 0
    try %#ok<TRYNC>
        fclose(fid);
    end
end
if exist(path, "file") == 2
    delete(path);
end
end
