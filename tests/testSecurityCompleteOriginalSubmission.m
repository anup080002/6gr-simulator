function ok=testSecurityCompleteOriginalSubmission()
% Real UPER/NIA2/PDCP/RLC handoff through production adapter, no RF claim.
% Original SMC receive is a declared protocol component boundary.
[dl,cd]=runtime('DL',1);[ul,cu,scope]=runtime('UL',0);
command=sixgr.rrc.asn1.NRAccessMessageCodec.encode('security_mode_command', ...
    struct('transaction_id',1,'ciphering_algorithm',"nea0",'integrity_algorithm',"nia2"));
issued=receipt(cd,'TX','security_command_issued',command.Bytes,uint8([]),0,0);
dl.activateTransmitIntegrity(cd.ContextID,issued);
p=dl.transmit('original-UPER-command',command.Bytes,0);
[~,done,~,status,observed]=dl.receive(p,.001);
assert(isempty(done)&&status=="authenticated_RRC_validation_pending");
actual=sixgr.rrc.asn1.NRAccessMessageCodec.decode('security_mode_command',observed.Payload);
assert(actual.Semantic.transaction_id==1&&string(actual.Semantic.integrity_algorithm)=="nia2");
pdcp=sixgr.l2.rlc18.RLCHeaderCodec.decodeAM(p.Bytes,12);
rx=receipt(cd,'RX','security_command_verified',command.Bytes,pdcp.Payload,0,1);
tx=receipt(cu,'TX','security_command_verified',command.Bytes,pdcp.Payload,0,1);
dl.commitReceivedSecurityCommand(observed.Token,rx,ul,cu.ContextID,tx);
complete=sixgr.rrc.asn1.NRAccessMessageCodec.encode('security_mode_complete',struct('transaction_id',1));
packet=ul.enqueuePacket('original-UPER-complete',complete.Bytes,.002);
submission=ul.originalLowerLayerSubmission(packet.PacketID);
ul.validateOriginalLowerLayerSubmission(submission);
assert(submission.TXIntegrityActive&&~submission.TXCipheringActive&&submission.SubmittedAtSample==2);
assert(submission.SecurityContextID==cu.ContextID&&submission.IntegrityAlgorithm=="128-NIA2");
expected=scope;expected.RRCTransactionID=1;
u0=ul.securityState();d0=dl.securityState();
bad=submission;bad.SubmittedAtSample=3;
reject(@()sixgr.rrc.applySubmittedSecurityComplete(ul,dl,bad,cu,cd,expected), ...
    'sixgr:protocol:OriginalSubmissionMismatch');
wrong=expected;wrong.RRCTransactionID=2;
reject(@()sixgr.rrc.applySubmittedSecurityComplete(ul,dl,submission,cu,cd,wrong), ...
    'sixgr:rrc:SecurityCompleteSubmission');
assert(isequaln(u0,ul.securityState())&&isequaln(d0,dl.securityState()));
result=sixgr.rrc.applySubmittedSecurityComplete(ul,dl,submission,cu,cd,expected);
u=ul.securityState();d=dl.securityState();
assert(result.SecurityActivated&&result.TXReceipt.EvidenceBoundary=="original_RRC_submission"&& ...
    isequal(result.Message.Bytes,complete.Bytes)&&u.TXCipheringActive&&d.RXCipheringActive&& ...
    ~u.RXCipheringActive&&~d.TXCipheringActive&&u.TXCount==u0.TXCount&&d.TXCount==d0.TXCount&& ...
    isequaln(submission,ul.originalLowerLayerSubmission(packet.PacketID)));
reject(@()sixgr.rrc.applySubmittedSecurityComplete(ul,dl,submission,cu,cd,expected), ...
    'sixgr:pdcp:SecurityActivation');
fprintf('SECURITY_COMPLETE_PRIVATE_SUBMISSION_PASS exact_UPER_NIA2=1 actual_RLC_handoff=1 peer_RX_not_fabricated=1 RF=0\n');
ok=true;
end
function [r,c,scope]=runtime(direction,numericDirection)
cfg=struct('UEID',"cell1-42",'BearerID',"SRB-1",'BearerType',"SRB",'SRBID',1, ...
    'LCID',1,'QFI',0,'PDCPSNBits',12,'RLCSNBits',12,'Direction',string(direction), ...
    'ConfigurationEpoch',1,'CipherAlgorithm',"NEA0",'IntegrityAlgorithm',"NIA0", ...
    'SampleRateHz',1000,'ClockEpoch',1);
scope=struct('ExecutionRunID',"private-complete-component",'UEID',cfg.UEID,'BearerID',cfg.BearerID, ...
    'ServingCell',1,'RNTI',42,'ConfigurationEpoch',1,'SampleRateHz',1000,'ClockEpoch',1, ...
    'ProtocolConfigurationSHA256',sixgr.l2.mac.MACHash.of(orderfields(cfg)));
cfg.OriginalConnectionScope=scope;r=sixgr.protocol.ProtocolRuntime(cfg);
c=struct('ContractVersion',"PDCP_endpoint_security/v1",'ContextID',"core-"+string(direction), ...
    'UEID',cfg.UEID,'BearerID',cfg.BearerID,'Direction',numericDirection,'ConfigurationEpoch',1, ...
    'CipherAlgorithm',"NEA0",'IntegrityAlgorithm',"128-NIA2", ...
    'CipherKey',uint8(16:31),'IntegrityKey',uint8(0:15),'SampleRateHz',1000,'ClockEpoch',1, ...
    'KeySource',"configured_preestablished_core_key");
r.stageSecurityContext('TX',c);r.stageSecurityContext('RX',c);
end
function r=receipt(c,endpoint,purpose,payload,pdu,count,sample)
r=struct('ContractVersion',"validated_RRC_security_boundary/v1",'ContextID',c.ContextID, ...
    'UEID',c.UEID,'BearerID',c.BearerID,'Direction',c.Direction,'ConfigurationEpoch',c.ConfigurationEpoch, ...
    'Endpoint',string(endpoint),'Purpose',string(purpose),'RRCTransactionID',1, ...
    'RRCPayloadSHA256',sixgr.protocol.ProtocolHash.bytes(payload), ...
    'PDCPPDUSHA256',sixgr.protocol.ProtocolHash.bytes(pdu), ...
    'OriginalObservationSHA256',sixgr.protocol.ProtocolHash.bytes(uint8([pdu payload])), ...
    'PDCPCount',count,'AtSample',sample,'SampleRateHz',1000,'ClockEpoch',1,'EvidenceBoundary',"declared_component");
end
function reject(f,id)
try,f();catch e,assert(string(e.identifier)==id,'Expected %s, got %s: %s',id,e.identifier,e.message);return;end
error('test:PairedSecurityGuard','Expected %s.',id);
end
