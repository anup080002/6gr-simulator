function ok = testRAN1LLSPUSCHFadingStages()
%TESTRAN1LLSPUSCHFADINGSTAGES Qualify per-RE CDL-C perfect/practical CSI.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
tmp = string(tempname);
mkdir(tmp);
cleanup = onCleanup(@() localCleanup(tmp)); %#ok<NASGU>

perfect = sixgr.lls.runLLS("configs/lls/pusch_cdlc_perfect_smoke.yaml", ...
    "OutputRoot", tmp, "RunTag", "perfect", "GeneratePlots", false);
practical = sixgr.lls.runLLS("configs/lls/pusch_cdlc_practical_smoke.yaml", ...
    "OutputRoot", tmp, "RunTag", "practical", "GeneratePlots", false);
tdl = sixgr.lls.runLLS("configs/lls/pusch_tdlc_perfect_smoke.yaml", ...
    "OutputRoot", tmp, "RunTag", "tdl_perfect", "GeneratePlots", false);
rank2 = sixgr.lls.runLLS("configs/lls/pusch_cdlc_rank2_perfect_smoke.yaml", ...
    "OutputRoot", tmp, "RunTag", "cdl_rank2", "GeneratePlots", false);

assert(all(perfect.TrialTable.ChannelModel == "CDL-C"));
assert(all(perfect.TrialTable.TrueChannelGridAvailable));
assert(all(perfect.TrialTable.TrueChannelGridVariance > 0), ...
    "CDL-C perfect channel must vary over the actual resource grid.");
assert(numel(unique(perfect.TrialTable.TrueChannelGridSHA256)) == height(perfect.TrialTable), ...
    "Independent trial channel seeds must produce distinct CDL-C channel grids.");
assert(all(contains(perfect.TrialTable.ChannelRealizationSource, ...
    "nrCDLChannel_path_gains_and_nrPerfectChannelEstimate")));
assert(all(perfect.TrialTable.ChannelEstimateEngine == "ideal_true_channel_test_oracle"), ...
    "Perfect mode must consume the exact simulated per-RE channel.");
assert(all(practical.TrialTable.ChannelEstimateEngine == "nrChannelEstimate"), ...
    "Practical mode must use DM-RS channel estimation, not the true-channel oracle.");
assert(all(practical.TrialTable.ChannelEstimationMode == "practical"));
assert(all(abs(perfect.TrialTable.MeasuredSNRdB-perfect.TrialTable.TargetSNRdB) < 0.5));
assert(all(abs(practical.TrialTable.MeasuredSNRdB-practical.TrialTable.TargetSNRdB) < 0.5));
assert(sum(perfect.TrialTable.CRCError) <= sum(practical.TrialTable.CRCError), ...
    "Practical estimation may not outperform perfect CSI for identical diagnostic streams.");
assert(all(tdl.TrialTable.ChannelModel == "TDL-C") && ...
    all(contains(tdl.TrialTable.ChannelRealizationSource, ...
    "nrTDLChannel_path_gains_and_nrPerfectChannelEstimate")) && ...
    all(tdl.TrialTable.TrueChannelGridVariance > 0), ...
    "TDL-C must be a real waveform filter with an exact varying per-RE channel grid.");
assert(all(rank2.TrialTable.NumLayers == 2) && ...
    all(rank2.TrialTable.NumTxPorts == 2) && ...
    all(rank2.TrialTable.NumRxAntennas == 2), ...
    "Rank-2 diagnostic must preserve layers, transmit ports, and receive antennas separately.");
assert(all(~rank2.TrialTable.CRCError), ...
    "High-SNR 2x2 rank-2 CDL-C perfect-CSI waveform trials must decode.");

fprintf("RAN1LLSPUSCHFadingStages: perfect errors=%d, practical errors=%d, full per-RE CDL-C grid verified.\n", ...
    sum(perfect.TrialTable.CRCError), sum(practical.TrialTable.CRCError));
ok = true;
end

function localCleanup(path)
if exist(path, "dir") == 7
    rmdir(path, "s");
end
end
