function ok=testRuntimeHARQFeedbackPublication()
% Independent receive outcomes, not CRC-derived ACK/NACK or inferred overhead.
cfg.phy.carrier.SubcarrierSpacing_kHz=15;
root=tempname; mkdir(root); cleanup=onCleanup(@()rmdir(root,'s')); %#ok<NASGU>
T=table(["DL";"DL";"DL";"UL"],ones(4,1),ones(4,1),[0;1;2;0], ...
    [3;4;5;3],[1;1;2;1],["a";"b";"a";"u"], ...
    ["grant-a";"grant-b";"grant-a";"grant-u"],[true;false;true;true], ...
    [true;false;true;true],false(4,1), ...
    'VariableNames',{'Direction','UEIndex','RNTI','HarqID','Slot', ...
    'SweepPointIndex','TBId','PHYGrantContextId','CurrentDecodeOK', ...
    'CombinedDecodeOK','IsRetransmission'});
F=table([1;1;2],["grant-a";"grant-b";"grant-a"],ones(3,1),ones(3,1), ...
    [3;4;5],[0;1;2],repmat("DL",3,1),["NACK";"ACK";"DTX"], ...
    [false;true;false],[true;true;false],["rx-a";"rx-b";"rx-c"], ...
    ["PUCCH";"PUSCH";"PUCCH"],true(3,1),false(3,1),[1;1;1], ...
    [100;200;300],[90;190;290],repmat(7.68e6,3,1), ...
    'VariableNames',{'SweepPointIndex','PHYGrantContextId','UEIndex','RNTI', ...
    'SourceSlot','HarqID','FeedbackForDirection','FeedbackOutcome', ...
    'ObservedAck','ReceiverUsable','ObservationID','UCITransport', ...
    'HARQFeedbackApplied','StaleFeedbackIgnored','BitIndex','AvailableAtSample', ...
    'ObservationEndSampleExclusive','ObservationSampleRateHz'});
runtime=struct('TimelineTable',T,'FeedbackObservationTable',F);
out=sixgr.truth.publishRuntimeHARQDiagnostics(cfg,fullfile(root,'air_interface'),runtime);
P=out.PacketTable;
assert(isequal(P.ACK(1:3),[0;1;0]) && isequal(P.NACK(1:3),[1;0;0]) && ...
    isequal(P.DTX(1:3),[0;0;1]));
assert(P.CombinedDecodeOK(1) && ~P.ACK(1) && ~P.CombinedDecodeOK(2) && P.ACK(2), ...
    'False ACK/NACK must remain visible; do not copy receiver data CRC into feedback.');
assert(all(isnan([P.ACK(4),P.NACK(4),P.DTX(4)])) && all(isnan(P.FeedbackBits)));
assert(isequal(P.DecodedHARQInformationBits(1:3),[1;1;0]));
assert(isequal(out.FeedbackObservationTable,F));
S=out.SummaryTable; rows=string(S.MetricKey)=="feedback_overhead";
assert(all(isnan(S.Value(rows))) && all(string(S.Availability(rows))=="not_available"));
rows=string(S.Entity)=="DL@canonical_slot_runtime" & string(S.Statistic)=="dtx_rate";
assert(S.Value(rows)==1/3);
readback=readtable(out.PacketCSV,'TextType','string','VariableNamingRule','preserve');
assert(isequaln(readback.ACK,P.ACK) && isequaln(readback.FeedbackBits,P.FeedbackBits));
assert(isequal(readback.FeedbackObservationID,P.FeedbackObservationID));
% A foreign sweep, UE, source slot, grant or process cannot supply a bit.
for field=["SweepPointIndex","UEIndex","RNTI","SourceSlot","HarqID"]
    bad=F; bad.(field)(1)=99;
    check=sixgr.truth.bindRuntimeHARQFeedbackEvidence(P,bad);
    assert(~check.FeedbackObservationAvailable(1) && isnan(check.ACK(1)));
end
bad=F; bad.PHYGrantContextId(1)="different-grant";
check=sixgr.truth.bindRuntimeHARQFeedbackEvidence(P,bad);
assert(~check.FeedbackObservationAvailable(1));
bad=F; bad.StaleFeedbackIgnored(1)=true; bad.HARQFeedbackApplied(1)=false;
check=sixgr.truth.bindRuntimeHARQFeedbackEvidence(P,bad);
assert(check.NACK(1)==1 && check.FeedbackApplied(1)==0 && check.FeedbackStaleIgnored(1)==1);
reject(@()sixgr.truth.bindRuntimeHARQFeedbackEvidence(P,[F;F(1,:)]), ...
    'sixgr:truth:AmbiguousHARQFeedbackObservation');
reject(@()sixgr.truth.bindRuntimeHARQFeedbackEvidence([P;P(1,:)],F), ...
    'sixgr:truth:DuplicateHARQAttemptObservation');
bad=F; bad.ReceiverUsable(3)=true;
reject(@()sixgr.truth.bindRuntimeHARQFeedbackEvidence(P,bad), ...
    'sixgr:truth:ContradictoryHARQFeedbackObservation');
bad=F; bad.AvailableAtSample(1)=89;
reject(@()sixgr.truth.bindRuntimeHARQFeedbackEvidence(P,bad), ...
    'sixgr:truth:InvalidHARQFeedbackClock');
none=sixgr.truth.publishRuntimeHARQDiagnostics(cfg,fullfile(root,'none','air_interface'), ...
    struct('TimelineTable',T));
assert(all(isnan(none.PacketTable.ACK)) && all(isnan(none.PacketTable.DTX)));
fprintf('RUNTIME_HARQ_FEEDBACK_PUBLICATION_PASS independent_ACK_NACK_DTX=3 foreign_identity_cases=6\n');
ok=true;
end

function reject(f,id)
try, f(); catch ex, assert(strcmp(ex.identifier,id),'%s',ex.message); return; end
error('test:ExpectedRejection','Expected %s',id);
end
