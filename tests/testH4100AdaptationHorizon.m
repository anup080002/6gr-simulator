function ok = testH4100AdaptationHorizon()
% Config-only check: no waveforms, forced attach deadlines or qualification.
root=fileparts(fileparts(mfilename('fullpath')));
scenario=fullfile(root,'simulator','configs','scenarios', ...
    'h4_100_cdlc100_connected_impaired_40db_adaptation.yaml');
parent=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_gate.yaml');
adapt=sixgr.lls6g.config.loadScenarioConfig(scenario);
assert(parent.get('run_control.total_slots')==200);
assert(adapt.get('run_control.total_slots')==100 && ...
    adapt.get('run_control.total_time_ms')==50 && ...
    adapt.get('run_control.measurement_slots')==100 && ...
    adapt.get('run_control.measurement_time_ms')==50 && ...
    adapt.get('simulation.n_slots')==100 && adapt.get('simulation.n_frames')==5 && ...
    adapt.get('simulation.n_subframes')==50 && adapt.get('simulation.min_duration_s')==.05 && ...
    adapt.get('random_access.num_slots')==100 && adapt.get('random_access.num_subframes')==50);

a=parent.toStruct(); b=adapt.toStruct();
fields=struct('meta',{{'scenario_id','description','purpose'}}, ...
    'run_control',{{'total_slots','total_time_ms','measurement_slots','measurement_time_ms'}}, ...
    'simulation',{{'n_frames','n_slots','n_subframes','min_duration_s'}}, ...
    'random_access',{{'num_slots','num_subframes'}},'output',{{'profile'}}, ...
    'config_inheritance',{{'parents','provenance'}});
for name=string(fieldnames(fields)).'
    a.(name)=rmfield(a.(name),fields.(name));
    b.(name)=rmfield(b.(name),fields.(name));
end
assert(isequaln(a,b), ...
    'Only duration and descriptive identity may change; retain PHY, clocks, seeds, thresholds and output fidelity.');
assert(isequal(adapt.SourceFiles(1:end-1),parent.SourceFiles));

cfg=sixgr.lls6g.buildInternalConfig(adapt,tempname);
assert(cfg.run.numTTI==100 && cfg.run.totalSlots==100 && cfg.run.totalTime_ms==50 && ...
    cfg.run.measurementSlots==100 && cfg.run.measurementTime_ms==50 && cfg.run.numFrames==5);
assert(cfg.phy.nTxAnt==64 && cfg.phy.nRxAnt==4 && ...
    cfg.phy.pdsch.maxRankDefault==4 && cfg.phy.pusch.maxRankDefault==4 && ...
    cfg.phy.csirs.numResources==8 && cfg.channel.snr_dB==40);
period=double(cfg.phy.csi.reportPeriodicitySlots); offset=double(cfg.phy.csi.reportOffsetSlots);
assert(period==20 && isequal((offset:period:99)+1,[19 39 59 79 99]));
for slot=[7 27 47 67 87]
    window=sixgr.truth.resolveTRSObservationWindow(cfg,slot);
    assert(window.ObservationStarts && isequal(window.AbsoluteSlotNumbers,[slot-1 slot]));
end
prach=sixgr.rach.PRACHConfig(cfg,'NumPRACHOccasions',1,'NumTrials',1);
assert(prach.NumSlots==100 && prach.NumSubframes==50 && ...
    prach.CarrierSCSkHz==30 && prach.NSizeGrid==273 && ...
    prach.NumRxAntennas==64 && prach.NumTxAntennas==4 && ...
    double(prach.FirstActiveOccasion.SlotIndex1)==10);
ok=true; fprintf('H4_100_ADAPTATION_HORIZON_PASS slots=100 scenario_accepted=0\n');
end
