function ok = testH4100ProductionTiming()
%TESTH4100PRODUCTIONTIMING Pin the H4 mu=1 Release-18 timing capability.

setup6GRSimToolkit("Verbose",false);
scenario=sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    "simulator","configs","scenarios", ...
    "h4_100_cdlc100_connected_impaired_40db_gate.yaml"));
cfg=sixgr.lls6g.buildInternalConfig(scenario, ...
    fullfile(tempdir,"h4_100_production_timing"));
policy=cfg.phy.frameStructure.TimingContext.Policy;
resolved=sixgr.phy.frame.TimingPolicyCatalog.resolveProduction( ...
    policy,1,1,["K0","K1","K2"]);

assert(string(resolved.CapabilityProfileID)== ...
    "38.214-v18.8.0-cap1-dmrs-pos0-mu1" && ...
    resolved.N1PDSCHProcessingTimeSymbols==10 && ...
    resolved.N2PUSCHPreparationTimeSymbols==12 && ...
    resolved.ControlToDataProcessingTimeSymbols.PDSCHToHARQACKN1==10 && ...
    resolved.ControlToDataProcessingTimeSymbols.PDCCHToPUSCHN2==12, ...
    "H4 must use the pinned Release-18 capability-1 mu=1 N1/N2 values.");
assert(isequal(resolved.AllowedK2,4) && any(resolved.AllowedK0==0) && ...
    isequal(resolved.AllowedK1,1:8), ...
    "H4 configured K0/K1/K2 rows must remain attached to the production policy.");

probe=struct("Direction","UL","ControlAbsoluteSlot",0, ...
    "ControlSymbolAllocation",double(cfg.phy.pdcch.symbolAllocation), ...
    "SymbolAllocation",double(cfg.phy.pusch.symbolAllocation), ...
    "HARQProcess",0);
decision=sixgr.phy.frame.TimingRelationEngine.resolveProductionGrant(cfg,probe);
assert(decision.Valid && decision.K2==4 && ...
    double(decision.DataAbsoluteSlot)==4 && ...
    string(decision.ReasonCode)=="production_timing_valid", ...
    "H4 slot-0 PDCCH must causally schedule its full-slot PUSCH in slot 4.");

% PRACH must use the same mu=1 carrier clock and complete run extent as the
% H4 carrier.  These values used to leak from the inherited 5-MHz fixture,
% producing a 15-kHz PRACH carrier inside a 30-kHz BWP.
prachCfg=sixgr.rach.PRACHConfig(cfg,"NumPRACHOccasions",1,"NumTrials",1);
assert(prachCfg.CarrierSCSkHz==30 && prachCfg.NSizeGrid==273 && ...
    prachCfg.NumSlots==200 && prachCfg.NumSubframes==100 && ...
    prachCfg.NumRxAntennas==64 && prachCfg.NumTxAntennas==4 && ...
    prachCfg.PRACHConfigurationIndex==157 && ...
    string(prachCfg.ResolvedPRACHFormat)=="B4", ...
    ["H4 PRACH must resolve index 157/B4 on the 30-kHz, 273-RB, " ...
    "64-RX/four-TX carrier and the complete 100-ms run clock."]);
assert(double(prachCfg.FirstActiveOccasion.SlotIndex1)==10 && ...
    sixgr.truth.isActivePRACHOccasion(cfg,10) && ...
    sixgr.util.resolveTDDSlotPartition(cfg,9).AllowUL, ...
    ["Index 157/B4 on the H4 mu=1 carrier must resolve its first " ...
    "occasion to one-based slot 10, a UL-capable TDD slot."]);
assert(sixgr.truth.isPRACHWaveformPreparationSlot(cfg,9) && ...
    ~sixgr.truth.isPRACHWaveformPreparationSlot(cfg,10), ...
    "The complete B4 OFDM buffer must be queued at one-based slot 9, " + ...
    "before its nonzero PRACH samples become active in slot 10.");
assert(double(cfg.random_access.occasion.frame)==0 && ...
    double(cfg.random_access.occasion.slot)==9 && ...
    double(cfg.random_access.occasion.symbol)==0 && ...
    double(cfg.random_access.occasion.frequency_index)==0, ...
    ["Strict four-step RA must install that same canonical index-157 " ...
    "occasion instead of retaining the inherited 15-kHz coordinate."]);
ra=sixgr.mac.ra.RAConfig(cfg,"RuntimeSlot",10, ...
    "RunId","h4_100_production_timing");
assert(ra.PRACHAbsoluteSlot==9 && ra.PRACHOccasionFrame==0 && ...
    ra.PRACHOccasionSlot==9 && ra.PRACHOccasionSymbol==0 && ...
    ra.PRACHFrequencyIndex==0 && string(ra.ResolvedPRACHFormat)=="B4", ...
    ["The strict four-step RA constructor must bind runtime slot 10 to " ...
    "the canonical H4 PRACH resource before waveform execution."]);

ok=true;
disp("H4_100_PRODUCTION_TIMING_PASS");
end
