function ok = testCanonicalOutputAuthorityNormalization()
%TESTCANONICALOUTPUTAUTHORITYNORMALIZATION Canonical YAML output is projected once.

setup6GRSimToolkit("Verbose", false);
cfg = struct();
cfg.output = struct( ...
    "backend", "filesystem", ...
    "artifact_contract_engine", localPolicy(true), ...
    "component_artifact_views", struct("enabled", true), ...
    "emit_disabled_audit_artifacts", true);
cfg.canonical_control = struct("output", struct( ...
    "artifact_contract_engine", localPolicy(true), ...
    "component_artifact_views", struct("enabled", true), ...
    "emit_disabled_audit_artifacts", true));

resolved = sixgr.lls6g.config.normalizeScenarioAliases(cfg);
assert(logical(resolved.output.artifact_contract_engine.enabled), ...
    "Canonical artifact-engine authority must be projected into output.");
assert(logical(resolved.output.component_artifact_views.enabled), ...
    "Canonical component-view authority must be projected into output.");
assert(logical(resolved.output.emit_disabled_audit_artifacts), ...
    "Canonical audit-output authority must be projected into output.");
assert(~isfield(resolved.canonical_control, "output"), ...
    "Normalized ScenarioConfig must retain only output as runtime authority.");

conflict = cfg;
conflict.output.artifact_contract_engine = localPolicy(false);
assertThrows(@() sixgr.lls6g.config.normalizeScenarioAliases(conflict), ...
    "sixgr:lls6g:config:ConflictingCanonicalOutputAuthority");
ok = true;
end

function assertThrows(fn, identifier)
threw = false;
try
    fn();
catch cause
    threw = true;
    assert(string(cause.identifier) == string(identifier));
end
assert(threw, "Expected %s.", identifier);
end

