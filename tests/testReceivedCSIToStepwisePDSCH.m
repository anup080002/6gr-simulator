function ok=testReceivedCSIToStepwisePDSCH()
% Actual received CSI -> bounded scheduled MCS -> received DCI/PDSCH -> UCI.
% Five-MHz component with declared initial TAG; not a full n40/BLER claim.
root=fileparts(fileparts(mfilename('fullpath')));
fixture=fullfile(root,'simulator','configs','scenarios', ...
    'lls_tdd_received_csi_stepwise_application_fixture.yaml');
[ok,state]=testReceivedCSIToScheduledPDSCH(false,fixture);
g=state.TestContinuationApplication.Grant;
p=g.MCSTransition;
assert(p.Enabled && p.RawTargetMCS>p.AppliedMCS && g.MCSIndex==p.AppliedMCS && ...
    state.TestContinuationApplication.ReceivedControl.ReceivedAssignment.MCS==p.AppliedMCS && ...
    state.TestPublishedDLTrials.MCSIndex==p.AppliedMCS && ...
    state.TestContinuationApplication.CRCPass && state.TestMCSTransitionFeedbackVerified);
assert(g.NumLayers==g.CSIReportProvenance.RI && g.PMI==g.CSIReportProvenance.PMI, ...
    'MCS admission must preserve the received spatial tuple.');
expected=sixgr.truth.projectMCSTransitionEvidence(g);
assert(string(state.TestPublishedDLTrials.MCSTransitionReceiptJSON)==expected.MCSTransitionReceiptJSON && ...
    string(state.TestPublishedDLTrials.MCSTransitionReceiptSHA256)==expected.MCSTransitionReceiptSHA256 && ...
    state.TestPublishedDLTrials.MCSTransitionAppliedMCS==g.MCSIndex, ...
    'Canonical publication must retain the original applied-MCS decision receipt.');
trial=state.TestPublishedDLTrials;
assert(string(trial.CRCOutcome)=="pass" && trial.ScheduledMCS==g.MCSIndex && ...
    trial.ScheduledMCSIndex==g.MCSIndex && string(trial.ScheduledModulation)==string(g.Modulation) && ...
    trial.ScheduledOperatingPointMatchesTransmitted && ~trial.LinkAdaptationScheduled && ...
    string(trial.ScheduledOperatingPointEvidenceStatus)=="materialized_from_executed_frozen_scheduler_grant", ...
    'Executed grant/CRC publication must remain available without a newly scheduled receiver feedback update.');
fprintf('RECEIVED_CSI_STEPWISE_PDSCH_PASS raw_target=%d applied=%d actual_feedback=%s full_n40=0\n', ...
    p.RawTargetMCS,p.AppliedMCS,string(state.TestMCSTransitionFeedback.FeedbackOutcome));
end
