function ok = testLLSBLERStatisticalMonotonicity()
%TESTLLSBLERSTATISTICALMONOTONICITY Sampling noise versus real inversion.

setup6GRSimToolkit("Verbose",false,"RunToolboxChecks",false);
observed = table([-4;-3;-2;-1;0], ...
    [0.99975;1;0.53375;0;0], ...
    [0.998585168933901;0.999040556710299;0.518265466670383;0;0], ...
    [0.999955867498042;1;0.549169770907562;0.000959443289701486;0.000959443289701486], ...
    'VariableNames',{'SNRdB','BLER','BLERLowerCI','BLERUpperCI'});
result = sixgr.lls.stats.evaluateBLERMonotonicity(observed);
assert(result.StatisticallyNoninverted && ~result.EmpiricalNonincreasing && ...
    result.InversionCount == 0 && ~result.MeasuredValuesModified, ...
    "Overlapping saturated-region confidence intervals must not create a false curve failure.");

inverted = table([-2;-1],[0.1;0.8],[0.08;0.77],[0.12;0.83], ...
    'VariableNames',{'SNRdB','BLER','BLERLowerCI','BLERUpperCI'});
bad = sixgr.lls.stats.evaluateBLERMonotonicity(inverted);
assert(~bad.StatisticallyNoninverted && bad.InversionCount == 1 && ...
    height(bad.Inversions) == 1 && ...
    bad.Inversions.ConfidenceSeparatedInversion(1), ...
    "A confidence-separated higher-SNR BLER increase must fail loudly.");

fprintf("PASS testLLSBLERStatisticalMonotonicity: sampling jitter passes and confidence-separated inversion fails.\n");
ok = true;
end
