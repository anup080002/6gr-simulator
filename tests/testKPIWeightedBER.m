function ok = testKPIWeightedBER()
%TESTKPIWEIGHTEDBER BER must be sum(BitErrors)/sum(BitsCompared), not row mean.

setup6GRSimToolkit("Verbose", false);

raw = struct();
raw.UL = table( ...
    repmat("UL", 2, 1), [1; 1], [true; true], [1; 9], [10; 990], ...
    [1000; 1000], [1000; 1000], [1; 1], [1; 2], ["ul_tb_1"; "ul_tb_2"], ...
    [0; 0], [0; 0], [0; 1], [1; 1], [1; 2], ...
    'VariableNames', {'Direction','Goodput_Mbps','CRCPass','BitErrors','BitsCompared', ...
    'TBSize_bits','GoodBits','Frame','Slot','TransportBlockId','HARQProcessId','RV','NDI', ...
    'AirInterfaceObservation_ms','TrialId'});
raw.DL = localDirectionTable("DL", 1);

out = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw);
ulBer = out.ReconstructionSummary(strcmp(string(out.ReconstructionSummary.KPIName), "UL_BER"), :);
expectedWeighted = 10 / 1000;
naiveMean = mean([1/10, 9/990]);
assert(abs(double(ulBer.ReconstructionValue(1)) - expectedWeighted) < 1e-12, ...
    "BER must use weighted sum(BitErrors)/sum(BitsCompared).");
assert(abs(double(ulBer.ReconstructionValue(1)) - naiveMean) > 1e-3, ...
    "Weighted BER test must not collapse to an unweighted per-row mean.");

ok = true;
end

function T = localDirectionTable(direction, goodput)
T = table( ...
    repmat(string(direction), 1, 1), goodput, true, 0, 1000, ...
    1000, 1000, 1, 1, string(direction + "_tb_1"), 0, 0, 0, 1, 1, ...
    'VariableNames', {'Direction','Goodput_Mbps','CRCPass','BitErrors','BitsCompared', ...
    'TBSize_bits','GoodBits','Frame','Slot','TransportBlockId','HARQProcessId','RV','NDI', ...
    'AirInterfaceObservation_ms','TrialId'});
end
