function [ok, checks] = testPUSCHFrozenCodebookAuthority(outputRoot)
%TESTPUSCHFROZENCODEBOOKAUTHORITY Declared PUSCH/frozen-grant boundary checks.
% This regression deliberately exposes missing frozen-codebook guards. The
% Channel*Mismatch/FrozenULCodebookTypeMismatch identifiers below are desired
% rejection contracts, not a claim that the current implementation has them.
%
% Scope: real nrPUSCHConfig objects, native resource accounting/TBS, and the
% production freeze/apply/dimension-assert APIs used by TX and RX. No waveform,
% received DCI, measured/accepted SRS, scheduler or HARQ lifecycle is created.
% The lower declared-grant fixture is explicitly non-strict; connected eight-
% port SRS/DCI restrictions are neither bypassed nor qualified by this test.
% Fixed values are adversarial component stimuli, not scenario defaults.
%
% Every check is collected independently and saved before the final verdict.
% Native matrix comparison uses the public R2026a API, not Toolbox internals.
% https://www.mathworks.com/help/releases/R2026a/5g/ref/nrpuschconfig.html

setup6GRSimToolkit('Verbose', false);
assert(strcmp(version('-release'), '2026a'), ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:PinnedRelease', ...
    'This declared boundary regression pins the R2026a public API.');
assert(exist('nrPUSCHConfig', 'class') == 8 && ...
    exist('nrPUSCHCodebook', 'file') == 2, ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:ToolboxRequired', ...
    'A missing native codebook implementation is not a passing skip.');
if nargin < 1 || strlength(string(outputRoot)) == 0
    repoRoot = fileparts(fileparts(mfilename('fullpath')));
    logRoot = fullfile(repoRoot, 'logs');
    if ~isfolder(logRoot), mkdir(logRoot); end
    outputRoot = tempname(logRoot);
end
outputRoot = char(string(outputRoot));
assert(~isfolder(outputRoot), ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:OutputExists', ...
    'Use a new output directory so prior diagnostic evidence is not overwritten.');
mkdir(outputRoot);

types = ["codebook1_ng1n4n1", "codebook1_ng1n2n2", ...
    "codebook2", "codebook3", "codebook4"];
prototype = struct('Check', "", 'NumPorts', NaN, 'NumLayers', 1, ...
    'RequestedCodebookType', "", 'Stage', "", 'ExpectedErrorID', "", ...
    'ObservedErrorID', "", 'Passed', false, 'FailureID', "", ...
    'Detail', "", 'EvidenceScope', ...
    "declared_frozen_grant_component_no_received_control_or_waveform");
rows = repmat(prototype, 0, 1);

record("matching_eight_port_object", 8, types(1), "TX_and_RX", "", ...
    @() localMatching(8));
record("same_authority_cached_grant", 8, types(1), "freeze_reuse", "", ...
    @localMatchingCache);
record("apply_restores_frozen_family_not_current_selector", 8, types(4), ...
    "apply_only_not_new_runtime_authority", "", @localApplyReplay);
record("changed_runtime_authority_remains_rejected", 8, types(1), ...
    "freeze_reuse", "sixgr:phy:grant:FrozenConfigurationAuthorityMismatch", ...
    @localChangedAuthority);

% The same lower guard is called by explicit-object TX and RX paths. These
% checks do not execute those facades or infer their other validation behavior.
stages = ["pusch_tx_before_waveform", "pusch_rx_after_config"];
fields = ["CodebookType", "TPMI", "TransformPrecoding"];
ids = ["sixgr:phy:grant:ChannelCodebookTypeMismatch", ...
    "sixgr:phy:grant:ChannelTPMIMismatch", ...
    "sixgr:phy:grant:ChannelTransformPrecodingMismatch"];
for stage = stages
    for k = 1:numel(fields)
        requestedType = types(1);
        if fields(k) == "CodebookType", requestedType = "codebook4"; end
        record("explicit_object_" + fields(k) + "_contradiction", 8, ...
            requestedType, stage, ids(k), ...
            @() localExplicitMismatch(fields(k), stage));
    end
end
record("same_identity_cached_request_family_contradiction", 8, ...
    "codebook4", "freeze_reuse", ...
    "sixgr:phy:grant:FrozenULCodebookTypeMismatch", @localCachedMismatch);

% CodebookType is inactive for one/two/four ports. The selector alone must
% not change the matrix or invalidate an otherwise identical cached grant.
for ports = [1 2 4]
    record("matching_inactive_port_object", ports, types(1), ...
        "TX_and_RX", "", @() localMatching(ports));
    for type = types
        record("inactive_selector_object_fresh_and_cached_grant", ports, ...
            type, "TX_RX_and_freeze_reuse", "", ...
            @() localInactiveSelector(ports, type));
    end
end

% Additional core-API checks retain the original 29 baseline cases above.
for type = types
    record("fresh_eight_port_family_native_matrix", 8, type, ...
        "freeze_and_object_guard", "", @() localFreshFamily(type));
end
record("missing_eight_port_family_catalog_unavailable", 8, "", ...
    "catalog", "", @localMissingFamilyCatalog);
record("missing_eight_port_family_projection_rejected", 8, "", ...
    "projection", "sixgr:phy:ul:PUSCHCodebookProjection:MissingCodebookType", ...
    @() sixgr.phy.ul.puschCodebookProjectionMatrix(1, 8, 0, false));
record("fractional_catalog_layers_unavailable", 8, types(1), "catalog", "", ...
    @() localFractionalCatalog(1 + 1e-10, 8));
record("fractional_catalog_ports_unavailable", 8 + 1e-10, types(1), "catalog", "", ...
    @() localFractionalCatalog(1, 8 + 1e-10));
invalidScalars = {[1.25 8 0], [1 8.5 0], [1 8 0.5], [1 8 1e-10]};
for k = 1:numel(invalidScalars)
    values = invalidScalars{k};
    record("fractional_projection_input_" + string(k), values(2), types(1), ...
        "projection", "sixgr:phy:ul:PUSCHCodebookProjection:BadParameters", ...
        @() sixgr.phy.ul.puschCodebookProjectionMatrix( ...
        values(1), values(2), values(3), false, types(1)));
end
record("nonboolean_transform_not_coerced", 8, types(1), "projection", ...
    "sixgr:phy:ul:PUSCHCodebookProjection:UnsupportedCombination", ...
    @() sixgr.phy.ul.puschCodebookProjectionMatrix(1, 8, 0, 2, types(1)));
record("invalid_inactive_family_still_rejected", 4, "invalid_family", "projection", ...
    "sixgr:phy:ul:PUSCHCodebookProjection:UnsupportedCombination", ...
    @() sixgr.phy.ul.puschCodebookProjectionMatrix(1, 4, 0, false, "invalid_family"));
record("explicit_empty_inactive_family_rejected", 4, "", "projection", ...
    "sixgr:phy:ul:PUSCHCodebookProjection:UnsupportedCombination", ...
    @() sixgr.phy.ul.puschCodebookProjectionMatrix(1, 4, 0, false, ""));
record("cached_fractional_TPMI_not_rounded", 8, types(1), "freeze_reuse", ...
    "sixgr:phy:grant:FrozenULTPMIMismatch", @() localFractionalCache("TPMI"));
record("cached_fractional_layers_not_rounded", 8, types(1), "freeze_reuse", ...
    "sixgr:phy:grant:FrozenULSpatialMismatch", @() localFractionalCache("NumLayers"));

checks = struct2table(rows);
scope = struct('Version', "declared_pusch_frozen_codebook_checks/v1", ...
    'MATLABRelease', string(version('-release')), ...
    'ReceivedControlEvidence', false, 'MeasuredSRSEvidence', false, ...
    'WaveformExecuted', false, 'ConnectedEightPortQualified', false, ...
    'HARQProcessQualified', false, 'TestSource', string(mfilename('fullpath')));
save(fullfile(outputRoot, 'declared_frozen_codebook_checks.mat'), 'checks', 'scope');
writetable(checks, fullfile(outputRoot, 'declared_frozen_codebook_checks.csv'));
fprintf('Declared frozen-codebook evidence: %s\n', outputRoot);
failures = checks(~checks.Passed, :);
for k = 1:height(failures)
    fprintf(2, '%s | ports=%g | %s | expected=%s observed=%s | %s | %s\n', ...
        char(failures.Check(k)), failures.NumPorts(k), ...
        char(failures.Stage(k)), char(failures.ExpectedErrorID(k)), ...
        char(failures.ObservedErrorID(k)), char(failures.FailureID(k)), ...
        char(failures.Detail(k)));
end
assert(isempty(failures), ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:Contract', ...
    '%d of %d declared frozen-codebook checks failed; see %s.', ...
    height(failures), height(checks), outputRoot);
ok = true;

    function record(name, ports, type, stage, expected, operation)
        row = prototype;
        row.Check = name; row.NumPorts = ports;
        row.RequestedCodebookType = type; row.Stage = stage;
        row.ExpectedErrorID = expected;
        try
            operation();
            row.Passed = strlength(expected) == 0;
            if ~row.Passed
                row.FailureID = "sixgr:test:PUSCHFrozenCodebookAuthority:MissingRejection";
                row.Detail = "Production API returned without the required rejection.";
            end
        catch ME
            row.ObservedErrorID = string(ME.identifier);
            row.Detail = string(ME.message);
            row.Passed = strlength(expected) > 0 && row.ObservedErrorID == expected;
            if ~row.Passed
                row.FailureID = row.ObservedErrorID;
                if strlength(row.FailureID) == 0
                    row.FailureID = "sixgr:test:PUSCHFrozenCodebookAuthority:UnidentifiedException";
                end
            end
        end
        rows(end+1, 1) = row; %#ok<AGROW>
    end
end

function localMatching(ports)
[~, ~, pusch, phy] = localFixture(ports);
localAssertNativeMatrix(phy, pusch);
sixgr.phy.grant.assertPHYGrantDimensions(phy, ...
    "pusch_tx_before_waveform", 'PUSCH', pusch);
sixgr.phy.grant.assertPHYGrantDimensions(phy, ...
    "pusch_rx_after_config", 'PUSCH', pusch);
end

function localFreshFamily(type)
[cfg, grant, pusch] = localFixture(8);
cfg.phy.pusch.CodebookType = type;
cfg.phy.pusch.codebookType = type;
grant.CodebookType = type;
pusch.CodebookType = char(type);
phy = sixgr.phy.grant.freezePHYGrant(cfg, "UL", grant, 'Frame', 0, 'Slot', 7);
localAssertNativeMatrix(phy, pusch);
assert(phy.PrecodingState.CodebookTypeApplicable && ...
    string(phy.PrecodingState.EffectiveCodebookType) == type, ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:EffectiveFamily', ...
    'Eight-port frozen metadata must identify the actual effective native family.');
sixgr.phy.grant.assertPHYGrantDimensions(phy, "declared_fresh_family", 'PUSCH', pusch);
end

function localMissingFamilyCatalog()
catalog = sixgr.phy.ul.puschCodebookCatalog(1, 8, false);
assert(~catalog.Valid && isempty(catalog.ValidTPMISet) && ...
    catalog.Reason == "missing_eight_port_codebook_type", ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:ImplicitFamily', ...
    'An absent eight-port family must not select an implicit default domain.');
end

function localFractionalCache(field)
[cfg, grant, ~, phy] = localFixture(8);
grant.PHYGrant = phy;
grant.(field) = double(grant.(field)) + 1e-10;
sixgr.phy.grant.freezePHYGrant(cfg, "UL", grant, 'Frame', 0, 'Slot', 7);
end

function localFractionalCatalog(layers, ports)
catalog = sixgr.phy.ul.puschCodebookCatalog(layers, ports, false, "codebook1_ng1n4n1");
assert(~catalog.Valid && isempty(catalog.ValidTPMISet), ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:RoundedCatalog', ...
    'Fractional catalog inputs must not be rounded into a valid domain.');
end

function localMatchingCache()
[cfg, grant, ~, phy] = localFixture(8);
grant.PHYGrant = phy;
again = sixgr.phy.grant.freezePHYGrant(cfg, "UL", grant, 'Frame', 0, 'Slot', 7);
assert(isequaln(again, phy), ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:ChangedMatchingSnapshot', ...
    'An identical cached request must preserve the entire frozen snapshot.');
end

function localApplyReplay()
[cfg, ~, pusch, phy] = localFixture(8);
cfg.phy.pusch.CodebookType = "codebook3";
cfg.phy.pusch.codebookType = "codebook3";
restored = sixgr.phy.grant.applyPHYGrantToConfig(cfg, phy);
assert(string(restored.phy.pusch.CodebookType) == string(pusch.CodebookType) && ...
    string(restored.phy.pusch.codebookType) == string(pusch.CodebookType) && ...
    double(restored.phy.pusch.TPMI) == double(pusch.TPMI) && ...
    logical(restored.phy.pusch.transformPrecoding) == logical(pusch.TransformPrecoding), ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:AmbientSelectorReplacedFrozen', ...
    'Applying a frozen grant must restore its family/TPMI/transform operands.');
% This tests application only, not permission to reuse a different current
% configuration authority. The separate negative preserves that strict guard.
end

function localChangedAuthority()
[cfg, grant, ~, phy] = localFixture(8);
grant.PHYGrant = phy;
cfg.meta.configHash = "declared_frozen_codebook_authority_B";
sixgr.phy.grant.freezePHYGrant(cfg, "UL", grant, 'Frame', 0, 'Slot', 7);
end

function localExplicitMismatch(field, stage)
[~, ~, pusch, phy] = localFixture(8);
original = double(nrPUSCHCodebook(1, 8, pusch.TPMI, ...
    pusch.TransformPrecoding, pusch.CodebookType));
switch field
    case "CodebookType"
        pusch.CodebookType = 'codebook4';
    case "TPMI"
        pusch.TPMI = 1;
    case "TransformPrecoding"
        pusch.TransformPrecoding = true; % Rank one remains a legal stimulus.
    otherwise
        error('sixgr:test:PUSCHFrozenCodebookAuthority:BadStimulus', ...
            'Unknown mismatch stimulus.');
end
changed = double(nrPUSCHCodebook(1, 8, pusch.TPMI, ...
    pusch.TransformPrecoding, pusch.CodebookType));
if field ~= "TransformPrecoding"
    assert(~isequal(changed, original), ...
        'sixgr:test:PUSCHFrozenCodebookAuthority:VacuousStimulus', ...
        'The selected valid family/TPMI mutation must change the native matrix.');
end
sixgr.phy.grant.assertPHYGrantDimensions(phy, stage, 'PUSCH', pusch);
end

function localCachedMismatch()
[cfg, grant, ~, phy] = localFixture(8);
grant.PHYGrant = phy;
grant.CodebookType = "codebook4";
assert(string(grant.GrantContextId) == string(phy.GrantContextId) && ...
    string(cfg.meta.configHash) == ...
    string(phy.ConfigurationAuthority.SourceConfigSHA256), ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:ChangedStimulusAuthority', ...
    'Only the explicit requested family may differ in this same-identity case.');
sixgr.phy.grant.freezePHYGrant(cfg, "UL", grant, 'Frame', 0, 'Slot', 7);
end

function localInactiveSelector(ports, type)
[cfg, grant, pusch, phy] = localFixture(ports);
baseline = double(nrPUSCHCodebook(1, ports, 0, false, pusch.CodebookType));
pusch.CodebookType = char(type);
assert(isequal(double(nrPUSCHCodebook(1, ports, 0, false, char(type))), baseline), ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:InactiveNativeMatrix', ...
    'The valid family selector must be inactive below eight ports.');
sixgr.phy.grant.assertPHYGrantDimensions(phy, ...
    "pusch_tx_before_waveform", 'PUSCH', pusch);
sixgr.phy.grant.assertPHYGrantDimensions(phy, ...
    "pusch_rx_after_config", 'PUSCH', pusch);
grant.CodebookType = type;
fresh = sixgr.phy.grant.freezePHYGrant(cfg, "UL", grant, 'Frame', 0, 'Slot', 7);
localAssertNativeMatrix(fresh, pusch);
assert(~fresh.PrecodingState.CodebookTypeApplicable && ...
    string(fresh.PrecodingState.EffectiveCodebookType) == "", ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:InactiveFamilyMetadata', ...
    'A valid inactive selector is not an effective selection-domain change.');
assert(isequaln(fresh.PrecodingState.MatrixLogicalPorts, ...
    phy.PrecodingState.MatrixLogicalPorts), ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:InactiveFrozenMatrix', ...
    'An inactive family selector must not change the frozen logical matrix.');
grant.PHYGrant = phy;
again = sixgr.phy.grant.freezePHYGrant(cfg, "UL", grant, 'Frame', 0, 'Slot', 7);
assert(isequaln(again, phy), ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:InactiveSelectorInvalidatedCache', ...
    'An inactive family selector alone must not invalidate a frozen request.');
end

function localAssertNativeMatrix(phy, pusch)
expected = double(nrPUSCHCodebook(pusch.NumLayers, pusch.NumAntennaPorts, ...
    pusch.TPMI, pusch.TransformPrecoding, pusch.CodebookType)).';
assert(isequal(size(phy.PrecodingState.MatrixLogicalPorts), size(expected)) && ...
    norm(double(phy.PrecodingState.MatrixLogicalPorts) - expected, 'fro') <= 1e-12, ...
    'sixgr:test:PUSCHFrozenCodebookAuthority:NativeFrozenMatrix', ...
    'Frozen logical weights must match the declared native codebook matrix.');
end

