function ok=testAcceptedSRSPublication()
% Authored publication-boundary fixtures, not waveform/adaptation qualification.
setup6GRSimToolkit('Verbose',false);
measurement=struct('MeasurementId',"accepted-A",'SignalType',"SRS",'TargetType',"UE", ...
    'TargetId',1,'ServingCell',1,'ProducerSlot',10,'AvailableSlot',11, ...
    'Valid',true,'RI',1,'PMI',0,'ResourceId',4, ...
    'SRSConfigurationContextID',"declared-config-A",'SRSNumPorts',2, ...
    'SRSConfigurationContextVersion',"srs_configuration_context/v1",'SRSConfigurationEpoch',2, ...
    'SRSResourceID',4,'SRSResourceIDsJSON',"[4,7]", ...
    'MeasurementSource',"declared_projection_fixture_not_PHY_execution", ...
    'MeasurementClockDomain',"receiver-clock-A",'MeasurementClockEpoch',2, ...
    'ObservationStartSample',100,'ObservationEndSampleExclusive',200, ...
    'ObservationSampleRateHz',1000,'ResultCompletedAtSample',210,'ResultAvailableAtSample',220);
capsule=sixgr.truth.captureAcceptedSRSSpatialDecision(measurement,101,1,0);
installation=struct('Version',"current_srs_installation/v1", ...
    'Source',"current_runtime_endpoint_installation",'UEIndex',1,'RNTI',101,'ServingCell',1, ...
    'NCellID',11,'ConfigurationEpoch',3,'ConfigurationContextID',"declared-current-config-B", ...
    'ReceiverNumElements',2,'ReceiverPortToElementMatrix',[1 0;0 1i]);
owner=struct('AcceptedSRSSpatialDecision',capsule, ...
    'SRSCurrentInstallation',installation, ...
    'AcceptedSRSDecisionContext',struct('Usable',true,'AgeSlots',12,'Status',"available"), ...
    'AcceptedSRSCausalUsable',true,'AcceptedSRSCausalAgeSlots',12,'AcceptedSRSCausalStatus',"available", ...
    'SRSCausalMeasurementId',"raw-B",'LastSuccessfulSRSSlot',21, ...
    'SRSCausalUsable',true,'SRSCausalAgeSlots',1,'SRSCausalStatus',"available", ...
    'SRSValid',true,'SRI',9,'SRSResourceIndicator',9);
unchanged=owner;
projection=sixgr.truth.projectAcceptedSRSDecisionEvidence(owner);
assert(isequaln(owner,unchanged),'Projection must not update the decision owner.');
assert(projection.AcceptedSRSMeasurementID=="accepted-A" && projection.RawSRSMeasurementID=="raw-B" && ...
    projection.AcceptedSRSRI==1 && projection.AcceptedSRSTPMI==0 && ...
    projection.AcceptedSRSProducerSlot==10 && projection.RawSRSLastSuccessfulSlot==21 && ...
    projection.AcceptedSRSResourceID=="4" && projection.ScheduledSRI==9, ...
    'Older computation source, newest sounding, and scheduled resource association must remain separate.');
assert(projection.AcceptedSRSSpatialDecisionJSON==string(jsonencode(capsule)) && ...
    projection.AcceptedSRSSpatialDecisionSHA256==sixgr.util.sha256Hex(string(jsonencode(capsule))));
assert(projection.AcceptedSRSDecisionContextSHA256== ...
    sixgr.util.sha256Hex(projection.AcceptedSRSDecisionContextJSON));
assert(projection.AcceptedSRSConfigurationContextID=="declared-config-A" && projection.AcceptedSRSNumPorts==2);
retained=jsondecode(projection.AcceptedSRSSpatialDecisionJSON);
assert(string(retained.SRSConfigurationContextVersion)==measurement.SRSConfigurationContextVersion && ...
    retained.SRSConfigurationEpoch==2 && retained.SRSResourceID==4 && ...
    string(retained.SRSResourceIDsJSON)==measurement.SRSResourceIDsJSON);
assert(projection.SRSCurrentInstallationJSON==string(jsonencode(sixgr.util.jsonSafeValue(installation))) && ...
    projection.SRSCurrentInstallationSHA256==sixgr.util.sha256Hex(projection.SRSCurrentInstallationJSON));
current=jsondecode(projection.SRSCurrentInstallationJSON);
matrix=current.ReceiverPortToElementMatrix;
assert(string(current.ConfigurationContextID)==installation.ConfigurationContextID && ...
    string(matrix.json_type)=="complex_array_split" && isequal(matrix.size(:).',[2 2]) && ...
    isequal(complex(matrix.real,matrix.imag),installation.ReceiverPortToElementMatrix));
% Only an original supplied/frozen capsule can provide current installation.
onlyFrozen=rmfield(owner,'SRSCurrentInstallation');
onlyFrozen.PHYGrant.LegacyGrantSnapshot.SRSCurrentInstallation=installation;
frozenProjection=sixgr.truth.projectAcceptedSRSDecisionEvidence(onlyFrozen);
assert(frozenProjection.SRSCurrentInstallationJSON==projection.SRSCurrentInstallationJSON);
same=owner; same.PHYGrant.LegacyGrantSnapshot.SRSCurrentInstallation=installation;
same=sixgr.truth.projectAcceptedSRSDecisionEvidence(same);
assert(same.SRSCurrentInstallationSHA256==projection.SRSCurrentInstallationSHA256);
missing=rmfield(owner,'SRSCurrentInstallation');
missing=sixgr.truth.projectAcceptedSRSDecisionEvidence(missing);
assert(missing.SRSCurrentInstallationJSON=="" && missing.SRSCurrentInstallationSHA256=="" && ...
    missing.AcceptedSRSSpatialDecisionSHA256==projection.AcceptedSRSSpatialDecisionSHA256);
missingTable=sixgr.truth.fillBlankCategoricalColumns(struct2table(missing,'AsArray',true),"ul_pusch_trials");
assert(missingTable.SRSCurrentInstallationJSON=="" && missingTable.SRSCurrentInstallationSHA256=="");
incomplete=owner; incomplete.SRSCurrentInstallation=rmfield(installation,'ConfigurationContextID');
expectError(@()sixgr.truth.projectAcceptedSRSDecisionEvidence(incomplete), ...
    'sixgr:truth:AcceptedSRSPublicationType');
changed=owner; changed.SRSCurrentInstallation.ConfigurationContextID="declared-current-config-C";
changed=sixgr.truth.projectAcceptedSRSDecisionEvidence(changed);
assert(changed.SRSCurrentInstallationSHA256~=projection.SRSCurrentInstallationSHA256 && ...
    changed.AcceptedSRSSpatialDecisionSHA256==projection.AcceptedSRSSpatialDecisionSHA256 && ...
    changed.AcceptedSRSCausalUsable==projection.AcceptedSRSCausalUsable, ...
    'Publication retains current/accepted disagreement without approving or rejecting a decision.');
conflict=owner; conflict.PHYGrant.LegacyGrantSnapshot.SRSCurrentInstallation=installation;
conflict.PHYGrant.LegacyGrantSnapshot.SRSCurrentInstallation.ReceiverPortToElementMatrix=[1 0;0 -1i];
expectError(@()sixgr.truth.projectAcceptedSRSDecisionEvidence(conflict), ...
    'sixgr:truth:AcceptedSRSPublicationMismatch');

% The supplied consumer already declared A stale. The exporter cannot give
% it B's freshness or replace it with B; explicit false is not missing data.
expired=owner; expired.AcceptedSRSCausalUsable=false;
expired.AcceptedSRSCausalAgeSlots=20; expired.AcceptedSRSCausalStatus="stale";
late=sixgr.truth.projectAcceptedSRSDecisionEvidence(expired);
assert(late.AcceptedSRSCausalUsable==0 && late.RawSRSCausalUsable==1 && ...
    late.AcceptedSRSCausalAgeSlots==20 && late.RawSRSCausalAgeSlots==1 && ...
    late.AcceptedSRSSpatialDecisionSHA256==projection.AcceptedSRSSpatialDecisionSHA256);
legacy=rmfield(owner,{'AcceptedSRSSpatialDecision','AcceptedSRSDecisionContext', ...
    'AcceptedSRSCausalUsable','AcceptedSRSCausalAgeSlots','AcceptedSRSCausalStatus'});
absent=sixgr.truth.projectAcceptedSRSDecisionEvidence(legacy);
assert(absent.AcceptedSRSMeasurementID=="" && absent.AcceptedSRSSpatialDecisionJSON=="" && ...
    isnan(absent.AcceptedSRSRI) && isnan(absent.AcceptedSRSCausalUsable) && ...
    absent.RawSRSMeasurementID=="raw-B",'Fresh raw SRS must not manufacture accepted history.');
canonical=sixgr.truth.canonicalizeLLSLiveSignalChainTable("ul_pusch_trials",struct2table(absent,'AsArray',true));
for name=string(fieldnames(absent)).'
    assert(isequaln(canonical.(name),absent.(name)), ...
        'Generic live canonicalization must not decorate absent SRS provenance: %s.',name);
end
assert(~sixgr.truth.isImmutableIdentityField("MeasuredSRSChannelEstimateSource"), ...
    'Protect only accepted/raw provenance prefixes, not all measurement names.');
old=owner; old.AcceptedSRSSpatialDecision=rmfield(capsule, ...
    {'MeasurementClockDomain','MeasurementClockEpoch','ObservationStartSample','ObservationEndSampleExclusive', ...
    'ObservationSampleRateHz','ResultCompletedAtSample','ResultAvailableAtSample'});
old=sixgr.truth.projectAcceptedSRSDecisionEvidence(old);
assert(old.AcceptedSRSMeasurementClockDomain=="" && isnan(old.AcceptedSRSMeasurementClockEpoch) && ...
    isnan(old.AcceptedSRSObservationStartSample),'Missing historical clock is never inferred from current capture.');
conflict=owner; conflict.PHYGrant.PrecodingState.AcceptedSRSSpatialDecision=capsule;
conflict.PHYGrant.PrecodingState.AcceptedSRSSpatialDecision.MeasurementId="other-source";
expectError(@()sixgr.truth.projectAcceptedSRSDecisionEvidence(conflict), ...
    'sixgr:truth:AcceptedSRSPublicationMismatch');

% Exercise the real grant-trace entrypoint, with no scheduler or RF run.
state=struct('CurrentSlot',22,'CurrentFrame',1,'CurrentSweepPointIndex',1, ...
    'CurrentSNR_dB',10,'ULGrantTraceTable',table(),'DLGrantTraceTable',table());
grant=owner; grant.UEIndex=1; grant.RNTI=101; grant.ServingCell=1;
grant.PRBSet=0:1; grant.SymbolAllocation=[0 14]; grant.NumLayers=1; grant.PMI=0;
grant.GrantContextId="declared-grant-A"; grant.FrozenGrantContextId="declared-grant-A";
state=sixgr.truth.CoupledTruthRuntime.appendGrantTraceRuntime(state,grant,"UL",struct());
grant.AcceptedSRSCausalUsable=false; grant.AcceptedSRSCausalAgeSlots=20; grant.AcceptedSRSCausalStatus="stale";
state.CurrentSlot=30; state.CurrentSweepPointIndex=2;
state=sixgr.truth.CoupledTruthRuntime.appendGrantTraceRuntime(state,grant,"UL",struct());
trials=state.ULGrantTraceTable;
assert(height(trials)==2 && all(trials.AcceptedSRSMeasurementID=="accepted-A") && ...
    all(trials.RawSRSMeasurementID=="raw-B") && isequal(trials.AcceptedSRSCausalUsable,[1;0]));
trials.RunID=["fixture-run-1";"fixture-run-2"]; trials.ExecutionID=["fixture-exec-1";"fixture-exec-2"];
trials.RandomSeed=[7;8]; trials.ChannelSeed=[9;10];
trials.ObservationID=["local-repeated-ID";"local-repeated-ID"];
trials.ReceiverWindowID=["local-repeated-window";"local-repeated-window"];
trials.AppliedPrecoderMatrixSHA256=repmat(sixgr.util.sha256Hex("declared-matrix"),2,1);
folder=tempname; mkdir(folder); cleanup=onCleanup(@()rmdir(folder,'s')); %#ok<NASGU>
path=fullfile(folder,'declared_projection_trials.csv');
sixgr.util.csvWriteTable(path,trials,'PreserveSchema',true,'RoundTripNumericText',true);
loaded=sixgr.util.csvReadTable(path,'TextType','string');
assert(isequal(string(loaded.AcceptedSRSSpatialDecisionJSON),trials.AcceptedSRSSpatialDecisionJSON));
assert(isequal(string(loaded.SRSCurrentInstallationJSON),trials.SRSCurrentInstallationJSON) && ...
    isequal(string(loaded.SRSCurrentInstallationSHA256),trials.SRSCurrentInstallationSHA256));
base=struct('pusch_table',loaded);
raw=struct('Slot',21,'UEIndex',1,'RNTI',101,'ServingCell',1,'ResourceID',9, ...
    'RIEstimate',2,'TPMIEstimate',1,'MeasurementId',"raw-B",'ObservationID',"raw-B-capture", ...
    'MeasurementClockDomain',"receiver-clock-B",'MeasurementClockEpoch',3, ...
    'ObservationStartSample',300,'ObservationEndSampleExclusive',400, ...
    'ObservationSampleRateHz',1000,'ResultAvailableAtSample',420, ...
    'SRSConfigurationContextID',"declared-config-B",'SRSNumPorts',4, ...
    'SRSConfigurationContextVersion',"srs_configuration_context/v1",'SRSConfigurationEpoch',3, ...
    'SRSResourceID',9,'SRSResourceIDsJSON',"[9,12]", ...
    'ExecutionID',"fixture-exec-1",'RunID',"fixture-run-1",'RandomSeed',7,'SweepPointIndex',1);
rawTable=struct2table(raw,'AsArray',true);
% Exercise the real persisted annotation path, including its generic blank
% decorator; unavailable historical identities must not become text tokens.
legacyRaw=rawTable; legacyRaw.SRSConfigurationContextID="";
legacyRaw.SRSConfigurationContextVersion=""; legacyRaw.SRSConfigurationEpoch=NaN;
legacyRaw.SRSResourceID=NaN; legacyRaw.SRSResourceIDsJSON="";
rawTable=[rawTable;legacyRaw];
annotated=sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("SRS",rawTable);
rawNames=["SRSConfigurationContextID","SRSConfigurationContextVersion", ...
    "SRSConfigurationEpoch","SRSResourceID","SRSResourceIDsJSON"];
for name=rawNames
    assert(isequaln(annotated.(name),rawTable.(name)), ...
        'Annotation must preserve exact supplied/missing raw identity: %s.',name);
end
rawPath=fullfile(folder,'declared_raw_srs.csv');
sixgr.util.csvWriteTable(rawPath,annotated,'PreserveSchema',true,'RoundTripNumericText',true);
base.srs_table=sixgr.util.csvReadTable(rawPath,'TextType','string');
public=sixgr.truth.buildLLSPublicOutputTables(base,sixgr.truth.llsOutputContract(), ...
    struct('logical_run_id',"publication-container",'run_id',17));
out=public.pusch_runtime_event_table;
for name=string(fieldnames(projection)).'
    assert(isequaln(out.(name),loaded.(name)),'Public PUSCH must preserve %s.',name);
end
assert(height(out)==2 && isequal(string(out.SourceRunID),trials.RunID) && ...
    isequal(double(out.RandomSeed),[7;8]) && isequal(double(out.SweepPointIndex),[1;2]) && ...
    isequal(string(out.AppliedPrecoderMatrixSHA256),trials.AppliedPrecoderMatrixSHA256));
rawOut=public.srs_measurement_table;
assert(height(rawOut)==2 && rawOut.MeasurementId(1)=="raw-B" && rawOut.RIEstimate(1)==2 && rawOut.TPMIEstimate(1)==1 && ...
    rawOut.MeasurementClockEpoch(1)==3 && rawOut.SourceRunID(1)=="fixture-run-1" && ...
    rawOut.SRSConfigurationContextID(1)=="declared-config-B" && rawOut.SRSNumPorts(1)==4 && ...
    ~ismember('AcceptedSRSMeasurementID',rawOut.Properties.VariableNames));
assert(all(contains(rawOut.SRSMeasurementEvidenceRole,"not_accepted")));
for name=rawNames
    assert(isequaln(rawOut.(name),base.srs_table.(name)), ...
        'Public raw SRS must retain its own versioned identity: %s.',name);
end
assert((ismissing(rawOut.SRSConfigurationContextID(2)) || rawOut.SRSConfigurationContextID(2)=="") && ...
    (ismissing(rawOut.SRSConfigurationContextVersion(2)) || rawOut.SRSConfigurationContextVersion(2)=="") && ...
    isnan(rawOut.SRSConfigurationEpoch(2)) && isnan(rawOut.SRSResourceID(2)));

% Admission evidence uses the same projection, including supplied stale=false.
ue=expired; ue.UEIndex=1; ue.RNTI=101; ue.ServingCell=1; ue.NumLayers=1;
ue.HasPendingRetransmission=false; ue.FeedbackKnownAtSlot=30;
ue.SchedulingBlockReason="accepted_srs_stale"; ue.HasTrafficDemand=true; ue.Active=false;
ue.ULBufferBytes=10; ue.AccessState="connected"; ue.ControlEligible=true;
ue.SchedulingEligible=false; ue.SRSRequired=true; ue.RankAuthority="accepted_srs";
ue.FeedbackValid=true; ue.FeedbackSourceSlot=10; ue.FeedbackDeliveredSlot=11;
ue.CausalFeedbackStatus="accepted_srs_stale"; ue.CausalFeedbackUsable=false;
state.ULQueueBits=80;
admission=sixgr.truth.schedulerAdmissionEvidence(state,struct(),ue,"UL");
assert(admission.RawSRSMeasurementID=="raw-B" && admission.AcceptedSRSMeasurementID=="accepted-A" && ...
    admission.AcceptedSRSCausalUsable==0 && admission.SRSCausalUsable==1 && admission.CandidateRank==1 && ...
    admission.SRSCurrentInstallationJSON==projection.SRSCurrentInstallationJSON && ...
    admission.SRSCurrentInstallationSHA256==projection.SRSCurrentInstallationSHA256);
fprintf('ACCEPTED_SRS_PUBLICATION_PASS accepted_A_raw_B grant_csv_public_admission waveform_execution=0\n');
ok=true;
end

function expectError(f,id)
try, f(); catch err, assert(strcmp(err.identifier,id)); return; end
error('sixgr:test:ExpectedFailure','Expected %s.',id);
end
