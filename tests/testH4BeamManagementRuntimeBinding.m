function ok = testH4BeamManagementRuntimeBinding()
%TESTH4BEAMMANAGEMENTRUNTIMEBINDING Verify measured P1/P2 and decoded TCI authority.

setup6GRSimToolkit("Verbose", false);
scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    "simulator/configs/scenarios/h4_100_beam_refinement_tci.yaml");
cfg = sixgr.lls6g.buildInternalConfig(scfg, ...
    fullfile(tempdir, "h4_beam_runtime_binding"));

state = struct();
state.CfgMobility = cfg;
state.CurrentSlot = 1;
state.CurrentSNR_dB = 20;
state.SweepPointIndex = 1;
state.BeamManagementRuntimeEnabled = true;
state.BeamManagementMachines = {sixgr.phy.beam.BeamManagementStateMachine("IDLE")};
state.BeamManagementStateTraceTable = table();
state.PendingBeamCRIByUE = NaN;
state.PendingTCIStateIDByUE = NaN;
state.PendingTCICodepointByUE = NaN;
state.PendingBeamSourceByUE = "";
state.ActiveTCIStateIDByUE = NaN;
state.ActiveTCICodepointByUE = NaN;
state.AppliedDataBeamCRIByUE = NaN;

state = sixgr.truth.CoupledTruthRuntime.stageMeasuredSSBBeamRuntime( ...
    state, 1, 0, -82, "unit_test_received_PBCH");
assert(state.BeamManagementMachines{1}.State == "TCI_PENDING");
if sixgr.rf.isNormalizedFixedSNRPowerReference(cfg)
    trace = state.BeamManagementStateTraceTable;
    assert(all(isnan(trace.MeasuredRSRPDBM)) && ...
        all(trace.MeasuredRSRPDBReUnitOccupiedREEs == -82) && ...
        all(trace.MeasuredPowerUnit == "dB_re_UnitOccupiedRE_Es") && ...
        all(trace.PowerReferencePlane == ...
            "normalized_fixed_esn0_unit_occupied_re_es"), ...
        "Normalized beam evidence must not be mislabeled as absolute dBm.");
end
assert(state.PendingBeamCRIByUE(1) == 0 && ...
    state.PendingTCIStateIDByUE(1) == 16 && ...
    state.PendingTCICodepointByUE(1) == 0);

% A causally received CSI-RS report may replace an untransmitted pending P1
% candidate.  It does not activate the beam: the matching TCI codepoint
% must still be independently decoded from PDCCH.
report = struct("Direction","DL", "UEIndex",1, "CRI",3, ...
    "CSIUCIDecodeOk",true, "SourceSignal","received_CSI_UCI", ...
    "ReportIdentity","H4-CSI-REPORT-3");
state = sixgr.truth.CoupledTruthRuntime.stageReceivedCSIBeamRuntime(state, report);
assert(state.BeamManagementMachines{1}.State == "TCI_PENDING" && ...
    state.PendingBeamCRIByUE(1) == 3 && ...
    state.PendingTCIStateIDByUE(1) == 19 && ...
    state.PendingTCICodepointByUE(1) == 3 && ...
    string(state.PendingBeamSourceByUE(1)) == "P2_CSI_RS");

wrong = table(1, 'VariableNames', {'DecodedDCITCICodepoint'});
[unchanged, accepted] = sixgr.truth.CoupledTruthRuntime. ...
    applyDecodedTCIBeamRuntime(state, 1, wrong);
assert(~accepted && unchanged.BeamManagementMachines{1}.State == "TCI_PENDING", ...
    "A mismatched decoded TCI codepoint must not activate the beam.");

refined = table(3, 'VariableNames', {'DecodedDCITCICodepoint'});
[state, accepted] = sixgr.truth.CoupledTruthRuntime. ...
    applyDecodedTCIBeamRuntime(state, 1, refined);
assert(accepted && state.BeamManagementMachines{1}.State == "DATA_ACTIVE");
assert(state.AppliedDataBeamCRIByUE(1) == 3 && ...
    state.ActiveTCIStateIDByUE(1) == 19 && ...
    state.ActiveTCICodepointByUE(1) == 3);
assert(height(state.BeamManagementStateTraceTable) == 6 && ...
    all(~state.BeamManagementStateTraceTable.GeometryOracleUsed), ...
    "The trace must contain causal state transitions without a geometry oracle.");

% Reproduce the connected runtime binding used by the H4 scenario.  The
% measured CRI is a Type-D spatial source; it must never overwrite the
% separately configured Type-A TRS timing source.
multiUser = struct("Enabled",true,"NumUsers",1,"RNTIStart",1, ...
    "ExecutionModel","slot_coupled_truth");
runtime = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfg,tempdir,multiUser,struct(),20);
runtime.CurrentSlot = 9;
runtime.CurrentServingIdx(:) = 1;
runtime.PendingBeamCRIByUE(1) = 3;
runtime.PendingTCIStateIDByUE(1) = 19;
runtime.PendingTCICodepointByUE(1) = 3;
[bound,~] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
    cfg,runtime,1,"DL");
qcl = bound.phy.pdsch.qclTCI;
assert(qcl.source_resource_id == 100 && ...
    qcl.timing_source_resource_id == 100 && ...
    qcl.spatial_source_resource_id == 3 && ...
    qcl.configuration_epoch == cfg.phy.pdsch.qclTCI.configuration_epoch && ...
    isequal(string(qcl.qcl_types),["A","D"]), ...
    ["Runtime TCI must keep TRS resource 100 as Type-A timing authority " ...
     "while binding received CRI 3 as the independent Type-D source."]);
trsCfg = sixgr.phy.trs.buildTRSConfigFromScenario( ...
    bound,"RuntimeSlot",8);
mapping = sixgr.phy.trs.generateTRSSymbolsAndIndices( ...
    trsCfg).ResourceMappingTable;
assert(any(mapping.NZPCSIRSResourceID == qcl.timing_source_resource_id), ...
    "The runtime Type-A source must occur in the actual TRS mapping.");
carrier = trsCfg.ToolboxCarrier;
sampleRate = 122.88e6;
firstSlot0 = min(double(mapping.Slot));
nominalStart = round(firstSlot0*1e-3*15/ ...
    double(carrier.SubcarrierSpacing)*sampleRate);
observation = sixgr.phy.waveform.WaveformObservationBuffer( ...
    nominalStart,nominalStart+1,sampleRate,1);
observation.append(sixgr.phy.waveform.WaveformChunk( ...
    complex(0),nominalStart),sampleRate);
prepared = struct( ...
    "ReceiverConfig",bound, ...
    "Tx",struct("ResourceMappingTable",mapping, ...
        "FirstSlot0Based",firstSlot0, ...
        "GridSlots",struct("Carrier",carrier)), ...
    "StrictConfig",struct("ConfigHash",trsCfg.ConfigHash));
received = struct("DetectionSuccess",true, ...
    "TRSTimingEstimateAvailable",true, ...
    "TRSTimingEstimateUsable",true, ...
    "EstimatedTimingOffset_samples",0);
recorded = sixgr.truth.recordSharedQCLTimingReference( ...
    struct(),prepared,observation,received,1,1);
assert(recorded.SharedQCLTimingReferences{1}.SourceResourceID == 100, ...
    ["The completed TRS observation must publish its Type-A resource " ...
     "identity even while CRI 3 owns the Type-D spatial relation."]);

ok = true;
end
