function ok = testH4BeamManagementRuntimeBinding()
%TESTH4BEAMMANAGEMENTRUNTIMEBINDING Verify measured P1/P2 and decoded TCI authority.

setup6GRSimToolkit("Verbose", false);
scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    "simulator/configs/scenarios/h4_100_beam_refinement_tci.yaml");
cfg = sixgr.lls6g.buildInternalConfig(scfg, ...
    fullfile(tempdir, "h4_beam_runtime_binding"));
localCheckSelectedSSBSINR(cfg);
localCheckRuntimeBinding(cfg);
% Rename resources without changing their list positions or beam matrices.
renamed = scfg.toStruct();
renamed.reference_signals.csi_rs_resource_ids = [17 5 33 9 41 13 57 21];
renamed.mimo_and_beam_management.ssb_to_initial_csi_resource_ids = [17 33 41 57];
renamedCfg = sixgr.lls6g.buildInternalConfig(renamed, tempname);
assert(isequal(renamedCfg.phy.csirs.resourceIDs, ...
    renamed.reference_signals.csi_rs_resource_ids));
localCheckRuntimeBinding(renamedCfg);
localCheckIdentityGuards(renamed, renamedCfg);
ok = true;
end

function localCheckRuntimeBinding(cfg)
ids = double(cfg.phy.csirs.resourceIDs);
state = struct();
state.CfgMobility = cfg;
state.CurrentSlot = 1;
state.CurrentSNR_dB = 20;
state.SweepPointIndex = 1;
state.BeamManagementRuntimeEnabled = true;
state.BeamManagementMachines = {sixgr.phy.beam.BeamManagementStateMachine("IDLE")};
state.BeamManagementStateTraceTable = table();
state.PendingBeamCRIByUE = NaN;
state.PendingTCIStateIDByUE = NaN;
state.PendingTCICodepointByUE = NaN;
state.PendingBeamSourceByUE = "";
state.ActiveTCIStateIDByUE = NaN;
state.ActiveTCICodepointByUE = NaN;
state.AppliedDataBeamCRIByUE = NaN;

state = sixgr.truth.CoupledTruthRuntime.stageMeasuredSSBBeamRuntime( ...
    state, 1, 0, -82, "unit_test_received_PBCH");
assert(state.BeamManagementMachines{1}.State == "TCI_PENDING");
if sixgr.rf.isNormalizedFixedSNRPowerReference(cfg)
    trace = state.BeamManagementStateTraceTable;
    assert(all(isnan(trace.MeasuredRSRPDBM)) && ...
        all(trace.MeasuredRSRPDBReUnitOccupiedREEs == -82) && ...
        all(trace.MeasuredPowerUnit == "dB_re_UnitOccupiedRE_Es") && ...
        all(trace.PowerReferencePlane == ...
            "normalized_fixed_esn0_unit_occupied_re_es"), ...
        "Normalized beam evidence must not be mislabeled as absolute dBm.");
end
assert(state.PendingBeamCRIByUE(1) == 0 && ...
    state.PendingTCIStateIDByUE(1) == 16 && ...
    state.PendingTCICodepointByUE(1) == 0);

% Exercise the separate P1 activation branch with its own handle-owned
% machine. A struct copy alone would share the existing mutable machine.
coarse = state;
coarse.BeamManagementMachines = {sixgr.phy.beam.BeamManagementStateMachine("IDLE")};
coarse.BeamManagementStateTraceTable = table();
coarse = sixgr.truth.CoupledTruthRuntime.stageMeasuredSSBBeamRuntime( ...
    coarse, 1, 1, -82, "declared_received_PBCH_identity_fixture");
assert(coarse.PendingBeamCRIByUE(1) == 2);
[coarse, accepted] = sixgr.truth.CoupledTruthRuntime.applyDecodedTCIBeamRuntime( ...
    coarse, 1, table(2,'VariableNames',{'DecodedDCITCICodepoint'}));
assert(accepted && coarse.BeamManagementMachines{1}.State == "P2_REFINING" && ...
    all(coarse.BeamManagementStateTraceTable.MeasuredResourceID(end-1:end) == ...
        "SSB-seeded-CSI-RS-" + string(ids(3))));

% A causally received CSI-RS report may replace an untransmitted pending P1
% candidate.  It does not activate the beam: the matching TCI codepoint
% must still be independently decoded from PDCCH.
report = struct("Direction","DL", "UEIndex",1, "CRI",3, ...
    "CSIUCIDecodeOk",true, "SourceSignal","received_CSI_UCI", ...
    "ReportIdentity","H4-CSI-REPORT-3");
state = sixgr.truth.CoupledTruthRuntime.stageReceivedCSIBeamRuntime(state, report);
assert(state.BeamManagementMachines{1}.State == "TCI_PENDING" && ...
    state.PendingBeamCRIByUE(1) == 3 && ...
    state.PendingTCIStateIDByUE(1) == 19 && ...
    state.PendingTCICodepointByUE(1) == 3 && ...
    string(state.PendingBeamSourceByUE(1)) == "P2_CSI_RS");
assert(state.BeamManagementStateTraceTable.MeasuredResourceID(end) == ...
    "CSI-RS-" + string(ids(report.CRI + 1)) && report.CRI == 3);

wrong = table(1, 'VariableNames', {'DecodedDCITCICodepoint'});
[unchanged, accepted] = sixgr.truth.CoupledTruthRuntime. ...
    applyDecodedTCIBeamRuntime(state, 1, wrong);
assert(~accepted && unchanged.BeamManagementMachines{1}.State == "TCI_PENDING", ...
    "A mismatched decoded TCI codepoint must not activate the beam.");

refined = table(3, 'VariableNames', {'DecodedDCITCICodepoint'});
[state, accepted] = sixgr.truth.CoupledTruthRuntime. ...
    applyDecodedTCIBeamRuntime(state, 1, refined);
assert(accepted && state.BeamManagementMachines{1}.State == "DATA_ACTIVE");
assert(state.AppliedDataBeamCRIByUE(1) == 3 && ...
    state.ActiveTCIStateIDByUE(1) == 19 && ...
    state.ActiveTCICodepointByUE(1) == 3);
assert(height(state.BeamManagementStateTraceTable) == 6 && ...
    all(~state.BeamManagementStateTraceTable.GeometryOracleUsed), ...
    "The trace must contain causal state transitions without a geometry oracle.");
assert(all(state.BeamManagementStateTraceTable.MeasuredResourceID(end-2:end) == ...
    "CSI-RS-" + string(ids(4))));

% A later CSI report can stage another beam while a grant using the active
% beam is still in flight. Pending refinement is not revocation of that
% already-activated codepoint and must not rewrite its frozen grant.
report.CRI = 5;
report.ReportIdentity = "H4-CSI-REPORT-5";
state = sixgr.truth.CoupledTruthRuntime.stageReceivedCSIBeamRuntime(state,report);
assert(state.BeamManagementMachines{1}.State == "TCI_PENDING" && ...
    state.PendingTCICodepointByUE(1) == 5 && state.ActiveTCICodepointByUE(1) == 3);
traceCount = height(state.BeamManagementStateTraceTable);
[state,accepted] = sixgr.truth.CoupledTruthRuntime.applyDecodedTCIBeamRuntime(state,1,refined);
assert(accepted && state.BeamManagementMachines{1}.State == "TCI_PENDING" && ...
    state.PendingTCICodepointByUE(1) == 5 && state.ActiveTCICodepointByUE(1) == 3 && ...
    height(state.BeamManagementStateTraceTable) == traceCount, ...
    'test:TCIPendingRevokedActiveGrant', ...
    'A new pending CSI candidate must not revoke the still-active TCI codepoint or activate the new beam.');
[state,accepted] = sixgr.truth.CoupledTruthRuntime.applyDecodedTCIBeamRuntime( ...
    state,1,table(5,'VariableNames',{'DecodedDCITCICodepoint'}));
assert(accepted && state.BeamManagementMachines{1}.State == "DATA_ACTIVE" && ...
    state.AppliedDataBeamCRIByUE(1) == 5 && state.ActiveTCIStateIDByUE(1) == 21 && ...
    isnan(state.PendingTCICodepointByUE(1)));
assert(all(state.BeamManagementStateTraceTable.MeasuredResourceID(end-3:end) == ...
    "CSI-RS-" + string(ids(6))));

% Reproduce the connected runtime binding used by the H4 scenario.  The
% measured CRI is a Type-D spatial source; it must never overwrite the
% separately configured Type-A TRS timing source.
multiUser = struct("Enabled",true,"NumUsers",1,"RNTIStart",1, ...
    "ExecutionModel","slot_coupled_truth");
runtime = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfg,tempdir,multiUser,struct(),20);
runtime.CurrentSlot = 9;
runtime.CurrentServingIdx(:) = 1;
runtime.PendingBeamCRIByUE(1) = 3;
runtime.PendingTCIStateIDByUE(1) = 19;
runtime.PendingTCICodepointByUE(1) = 3;
[bound,~] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
    cfg,runtime,1,"DL");
qcl = bound.phy.pdsch.qclTCI;
assert(qcl.source_resource_id == 100 && ...
    qcl.timing_source_resource_id == 100 && ...
    qcl.spatial_source_resource_id == ids(4) && ...
    qcl.configuration_epoch == cfg.phy.pdsch.qclTCI.configuration_epoch && ...
    isequal(string(qcl.qcl_types),["A","D"]), ...
    ["Runtime TCI must keep TRS resource 100 as Type-A timing authority " ...
     "while binding received CRI 3 as the independent Type-D source."]);
% Resolve the burst's first resource from the installed calendar. The H4
% periodic burst starts at one-based slot 7, not the older fixture's slot 8.
trsWindow = sixgr.truth.resolveTRSObservationWindow(bound,runtime.CurrentSlot);
trsStart = min(trsWindow.AbsoluteSlotNumbers)+1;
assert(trsStart < runtime.CurrentSlot && ...
    sixgr.truth.resolveTRSObservationWindow(bound,trsStart).ObservationStarts);
trsCfg = sixgr.phy.trs.buildTRSConfigFromScenario( ...
    bound,"RuntimeSlot",trsStart);
mapping = sixgr.phy.trs.generateTRSSymbolsAndIndices( ...
    trsCfg).ResourceMappingTable;
assert(any(mapping.NZPCSIRSResourceID == qcl.timing_source_resource_id), ...
    "The runtime Type-A source must occur in the actual TRS mapping.");
carrier = trsCfg.ToolboxCarrier;
sampleRate = 122.88e6;
firstSlot0 = min(double(mapping.Slot));
nominalStart = round(firstSlot0*1e-3*15/ ...
    double(carrier.SubcarrierSpacing)*sampleRate);
observation = sixgr.phy.waveform.WaveformObservationBuffer( ...
    nominalStart,nominalStart+1,sampleRate,1);
observation.append(sixgr.phy.waveform.WaveformChunk( ...
    complex(0),nominalStart),sampleRate);
prepared = struct( ...
    "ReceiverConfig",bound, ...
    "Tx",struct("ResourceMappingTable",mapping, ...
        "FirstSlot0Based",firstSlot0, ...
        "GridSlots",struct("Carrier",carrier)), ...
    "StrictConfig",struct("ConfigHash",trsCfg.ConfigHash));
received = struct("DetectionSuccess",true, ...
    "TRSTimingEstimateAvailable",true, ...
    "TRSTimingEstimateUsable",true, ...
    "EstimatedTimingOffset_samples",0);
recorded = sixgr.truth.recordSharedQCLTimingReference( ...
    struct(),prepared,observation,received,1,1);
assert(recorded.SharedQCLTimingReferences{1}.SourceResourceID == 100, ...
    ["The completed TRS observation must publish its Type-A resource " ...
     "identity even while CRI 3 owns the Type-D spatial relation."]);

end

function localCheckIdentityGuards(scenario, cfg)
resolve = @sixgr.phy.refsig.resolveCSIResourceIdentity;
[ids, cri] = resolve(cfg, [17 33 5], "resource_id");
assert(isequal(ids,[17 33 5]) && isequal(cri,[0 2 1]));
[ids, cri] = resolve(cfg, [0;2;1], "cri");
assert(isequal(ids,[17;33;5]) && isequal(cri,[0;2;1]));
localExpectError(@()resolve(cfg,0,"resource_id"), ...
    "sixgr:phy:refsig:UnknownCSIResourceID");
localExpectError(@()resolve(cfg,8,"cri"), ...
    "sixgr:phy:refsig:CSIResourceOrdinalOutOfRange");
missing = cfg; missing.phy.csirs = rmfield(missing.phy.csirs,'resourceIDs');
localExpectError(@()resolve(missing,0,"cri"), ...
    "sixgr:phy:refsig:InvalidCSIResourceIDs");
duplicate = cfg; duplicate.phy.csirs.resourceIDs(2) = duplicate.phy.csirs.resourceIDs(1);
localExpectError(@()resolve(duplicate,0,"cri"), ...
    "sixgr:phy:refsig:InvalidCSIResourceIDs");
short = cfg; short.phy.csirs.resourceIDs(end) = [];
localExpectError(@()resolve(short,0,"cri"), ...
    "sixgr:phy:refsig:InvalidCSIResourceIDs");
% Singleton identity component, not a declaration of a new H4 waveform.
single = struct('phy',struct('csirs',struct('numResources',1,'resourceIDs',17)));
[id, cri] = resolve(single,17,"resource_id");
assert(id==17 && cri==0 && resolve(single,0,"cri")==17);
localExpectError(@()resolve(single,17,"cri"), ...
    "sixgr:phy:refsig:CSIResourceOrdinalOutOfRange");
localExpectError(@()resolve(single,0,"resource_id"), ...
    "sixgr:phy:refsig:UnknownCSIResourceID");

unknown = scenario;
unknown.mimo_and_beam_management.ssb_to_initial_csi_resource_ids(1) = 0;
localExpectError(@()sixgr.lls6g.buildInternalConfig(unknown,tempname), ...
    "sixgr:phy:refsig:UnknownCSIResourceID");
missing = scenario;
missing.reference_signals = rmfield(missing.reference_signals,'csi_rs_resource_ids');
localExpectError(@()sixgr.lls6g.buildInternalConfig(missing,tempname), ...
    "sixgr:lls6g:config:InvalidCSIRSResourceIDs");
duplicate = scenario;
duplicate.reference_signals.csi_rs_resource_ids(2) = ...
    duplicate.reference_signals.csi_rs_resource_ids(1);
localExpectError(@()sixgr.lls6g.buildInternalConfig(duplicate,tempname), ...
    "sixgr:lls6g:config:InvalidCSIRSResourceIDs");
missingMap = scenario;
missingMap.mimo_and_beam_management = rmfield( ...
    missingMap.mimo_and_beam_management,'ssb_to_initial_csi_resource_ids');
localExpectError(@()sixgr.lls6g.buildInternalConfig(missingMap,tempname), ...
    "sixgr:lls6g:config:InvalidSSBToCSIResourceMap");
end

function localExpectError(call, identifier)
try
    call();
catch cause
    assert(string(cause.identifier)==identifier, ...
        'Expected %s, got %s: %s',identifier,cause.identifier,cause.message);
    return;
end
error('test:MissingCSIIdentityRejection','Expected %s.',identifier);
end

function localCheckSelectedSSBSINR(cfg)
% Declared adapter fixture, not a new physical SSB qualification. Exercise
% the production PBCH completion callback with unlike candidate/DM-RS SINRs.
multi=struct('Enabled',true,'NumUsers',1,'RNTIStart',1, ...
    'ExecutionModel','slot_coupled_truth');
root=tempname; mkdir(root);
base=sixgr.truth.CoupledTruthRuntime.initialize(cfg,root,multi,struct(),20);
base.CurrentSlot=15; base.CurrentServingIdx(:)=1;
row=struct2table(struct('Slot',1,'Status',"PASS",'CRCPass',true, ...
    'ServingCell',1,'SSBIndex',1,'SelectedSSBIndex',1,'SelectedBeamIndex',2, ...
    'SelectedBeamFlag',true,'SelectionMetricValue_dB',-15, ...
    'SelectionSource',"declared_selected_ssb_adapter_fixture", ...
    'SS_RSRP_dBm',NaN,'SS_RSRP_dB_re_UnitOccupiedRE_Es',-15, ...
    'SS_SINR_dB',25.58,'ReceiverHestSINR_dB',27.38, ...
    'SSSINRMeasurementMethod',"fixture_sss_received_measurement", ...
    'SSSINRReferencePlane',"fixture_received_sss_resource_elements", ...
    'ObservationStartSample',0,'ObservationEndSampleExclusive',860160, ...
    'ObservationSampleRateHz',122.88e6,'ObservationCompletionTime_s',.007, ...
    'ObservationDeliverySlot',15,'ObservationDeliveryTime_s',.007, ...
    'ResultAvailableAtSample',860160));
if sixgr.rf.isNormalizedFixedSNRPowerReference(cfg)
    row.PowerReferencePlane="normalized_fixed_esn0_unit_occupied_re_es";
else
    row.PowerReferencePlane="absolute_calibrated_receiver_measurement";
    row.SS_RSRP_dBm=-82; row.SS_RSRP_dB_re_UnitOccupiedRE_Es=NaN;
    row.SelectionMetricValue_dB=-82;
end
candidates=repmat(row,3,1);
candidates.SSBIndex=[0;2;1]; candidates.SelectedBeamFlag=[false;false;true];
candidates.SS_SINR_dB=[45;3;25.58];
state=sixgr.truth.CoupledTruthRuntime.applyPBCHTrial(base,1,candidates);
trace=state.BeamManagementStateTraceTable;
assert(height(trace)==3 && all(trace.MeasuredSINRDB==row.SS_SINR_dB), ...
    'test:SelectedSSBSINRDropped', ...
    'P1 must keep selected SS-SINR, not another candidate or PBCH DM-RS SINR.');
assert(all(trace.MeasuredSINRQuantity=="SS-SINR") && ...
    all(trace.MeasuredSINRMethod==row.SSSINRMeasurementMethod) && ...
    all(trace.MeasuredSINRReferencePlane==row.SSSINRReferencePlane) && ...
    all(trace.MeasurementSourceSSBIndex==1) && ...
    all(trace.MeasurementSourceSlot1Based==1) && ...
    all(trace.MeasurementAvailableSlot1Based==15) && ...
    all(trace.MeasurementResultAvailableAtSample==860160));
path=fullfile(root,'beam_trace.csv');
sixgr.util.csvWriteTable(path,trace,'PreserveSchema',true,'RoundTripNumericText',true);
saved=sixgr.util.csvReadTable(path,'TextType','string');
assert(isequal(saved.MeasuredSINRDB,trace.MeasuredSINRDB) && ...
    isequal(saved.MeasuredSINRMethod,trace.MeasuredSINRMethod) && ...
    isequal(saved.MeasurementResultAvailableAtSample,trace.MeasurementResultAvailableAtSample));
% NaN remains unknown even when PBCH DM-RS and other candidates are finite.
row.SS_SINR_dB=NaN;
base.BeamManagementMachines={sixgr.phy.beam.BeamManagementStateMachine("IDLE")};
missing=sixgr.truth.CoupledTruthRuntime.applyPBCHTrial(base,1,row);
assert(all(isnan(missing.BeamManagementStateTraceTable.MeasuredSINRDB)));
row=removevars(row,{'SS_SINR_dB','SSSINRMeasurementMethod','SSSINRReferencePlane'});
base.BeamManagementMachines={sixgr.phy.beam.BeamManagementStateMachine("IDLE")};
absent=sixgr.truth.CoupledTruthRuntime.applyPBCHTrial(base,1,row);
assert(all(isnan(absent.BeamManagementStateTraceTable.MeasuredSINRDB)) && ...
    all(absent.BeamManagementStateTraceTable.MeasuredSINRMethod==""));
end
