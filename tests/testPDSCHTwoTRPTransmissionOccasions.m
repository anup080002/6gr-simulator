function ok = testPDSCHTwoTRPTransmissionOccasions()
%TESTPDSCHTWOTRPTRANSMISSIONOCCASIONS Execute two canonical TX/RX paths.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
fixture = StrictPDSCHChainFixture.create(2);
data = fixture.Assignment.toStruct();
data.TCIStateId = 0;
data.TransmissionConfigurationIndication = 0;
data.AssignmentId = string(data.AssignmentId) + "-TWO-TRP";
assignment = sixgr.pdsch.PDSCHSchedulingAssignment(data);
context = StrictPDSCHChainFixture.integrationContext( ...
    assignment, fixture.PrecoderBundle);
binding = sixgr.pdsch.PDSCHIntegrationValidator.bind( ...
    assignment, context, fixture.PrecoderBundle);

tbDigest = sixgr.pdsch.PDSCHMultiTRPExecutor. ...
    transportBlockDigest(fixture.TransportBlocks);
resourceTruth = struct( ...
    "ResourcePlanClass", class(fixture.ResourcePlan), ...
    "ExactDataRECount", fixture.ResourcePlan.ExactDataRECount);
trp = struct( ...
    "TRPId", {1,2}, ...
    "TCIStateId", {data.TCIStateId,data.TCIStateId}, ...
    "SlotOffset", {0,0}, ...
    "PrecoderBundle", ...
        {fixture.PrecoderBundle,fixture.PrecoderBundle}, ...
    "DMRSPTRSPlan", {resourceTruth,resourceTruth}, ...
    "PowerScaling", {0.8,0.55}, ...
    "TBIdentityDigest", {tbDigest,tbDigest}, ...
    "HARQProcessId", {data.HARQProcessId,data.HARQProcessId});
spec = struct( ...
    "Scheme","repetition_noncoherent", ...
    "TRPs",trp, ...
    "TBIdentityDigest",tbDigest, ...
    "HARQProcessId",data.HARQProcessId);
plan = sixgr.pdsch.PDSCHIntegrationValidator. ...
    transmissionOccasions(assignment, binding, spec);
assert(numel(plan.Occasions) == 2 ...
    && all([plan.Occasions.AbsoluteSlot] == data.PDSCHAbsoluteSlot));

result = sixgr.pdsch.PDSCHMultiTRPExecutor.execute( ...
    fixture.TransportBlocks, assignment, fixture.ResourcePlan, ...
    fixture.Carrier, fixture.ReferenceConfig, fixture.ReceiverConfig, ...
    context, spec);
assert(result.ActualCanonicalOccasionCount == 2 ...
    && result.CRCPass && result.ExactTransportBlockRecovery);
assert(all(cellfun(@(x) x.Source ...
        == "explicit_pdsch_dlsch_production_chain", ...
        result.Transmitters)) ...
    && all(cellfun(@(x) x.Source ...
        == "explicit_pdsch_dlsch_production_receiver", ...
        result.Receivers)) ...
    && all(cellfun(@(x) x.CRCPass, result.Receivers)));
observed = result.PerOccasionDescrambledLLR(:, 1);
expectedCombined = observed{1} + observed{2};
assert(isequal(result.CombinedRateMatchedLLR{1}, expectedCombined) ...
    && result.LLRSource == "PDSCHReceiver.DescrambledLLR" ...
    && result.CombinationRule ...
        == "soft_llr_sum_after_per_occasion_equalization");
assert(isequal(result.TransportBlocks{1}, fixture.TransportBlocks{1}) ...
    && result.CombinedDecode{1}.CRCPass);

bad = spec;
bad.Scheme = "coherent_joint_transmission";
localAssert(@() sixgr.pdsch.PDSCHIntegrationValidator. ...
    transmissionOccasions(assignment, binding, bad), ...
    "sixgr:pdsch:UnsupportedMultiTRPScheme");
badId = spec;
badId.TRPs(2).TBIdentityDigest = "OTHER";
localAssert(@() sixgr.pdsch.PDSCHIntegrationValidator. ...
    transmissionOccasions(assignment, binding, badId), ...
    "sixgr:pdsch:MultiTRPHARQIdentityMismatch");
badActualTB = spec;
badActualTB.TBIdentityDigest = string(repmat('0', 1, 64));
badActualTB.TRPs(1).TBIdentityDigest = badActualTB.TBIdentityDigest;
badActualTB.TRPs(2).TBIdentityDigest = badActualTB.TBIdentityDigest;
localAssert(@() sixgr.pdsch.PDSCHMultiTRPExecutor.execute( ...
    fixture.TransportBlocks, assignment, fixture.ResourcePlan, ...
    fixture.Carrier, fixture.ReferenceConfig, fixture.ReceiverConfig, ...
    context, badActualTB), ...
    "sixgr:pdsch:MultiTRPTransportBlockIdentityMismatch");

fprintf([ ...
    'PDSCH two-TRP: 2 canonical TX/RX occasions, actual receiver ' ...
    'LLR sum, combined CRC and exact TB passed.\\n']);
ok = true;
end

function localAssert(fn,id)
try
    fn();
catch ME
    assert(string(ME.identifier)==id, ...
        "Expected %s, observed %s.", id, string(ME.identifier));
    return;
end
error("testPDSCHTwoTRPTransmissionOccasions:MissingError", ...
    "Expected %s.",id);
end
