function testToolboxPeakDoesNotTreatCyclicShiftsAsAmbiguity(testCase)
% nrPRACHDetect reports a shared root-sequence correlation vector. Equal
% cyclic-shift peaks are not evidence that several preambles were decoded.
cfg = sixgr.rach.PRACHConfig(struct( ...
    "ScenarioName", "toolbox_peak_ambiguity_regression", ...
    "CarrierFrequencyHz", 700e6, ...
    "DuplexMode", "FDD", ...
    "NSizeGrid", 52, ...
    "PRACHConfigurationIndex", 16, ...
    "PRACHSubcarrierSpacing", 1.25, ...
    "PRACHFormat", "0", ...
    "ChannelModel", "AWGN"), ...
    "PreambleIndex", 7, ...
    "DetectionThresholdMode", "fixed", ...
    "DetectionThreshold", 0.02);
occasion = sixgr.rach.mapPRACHToOccasion(cfg, "OccasionIndex", 1);
tx = sixgr.rach.generatePRACHWaveform( ...
    cfg, "Occasion", occasion, "PreambleIndex", 7);
det = sixgr.rach.PRACHDetector(tx.Waveform, cfg, ...
    "Occasion", occasion, ...
    "CandidatePreambles", 0:63, ...
    "DetectorBackend", "toolbox_peak", ...
    "DetectionThresholdMode", "fixed", ...
    "DetectionThreshold", 0.02);

verifyTrue(testCase, logical(det.Detected));
verifyEqual(testCase, double(det.DetectedPreambleIndex), 7);
verifyEqual(testCase, double(det.CandidatesAboveThreshold), 1);
verifyFalse(testCase, logical(det.MultiCandidateAboveThreshold));
verifyEqual(testCase, ...
    double(det.DetInfo.DetectedPreambleIndicesRaw), 7);
end

function localVerifyError(testCase, call, expectedID)
try
    call();
    verifyFail(testCase, "Expected typed error was not raised.");
catch ME
    verifyEqual(testCase, string(ME.identifier), string(expectedID));
end
end

