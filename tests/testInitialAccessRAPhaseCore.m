    [resolved.Msg2Slot, resolved.Msg3Slot, resolved.Msg4Slot, ...
    resolved.SetupCompleteSlot], [1 4 6 7]);

outside = cfg;
outside.random_access.timing.rar_processing_delay_slots = ...
    outside.random_access.ra_response_window_slots + 1;
localVerifyError(testCase, @() sixgr.mac.ra.RAConfig(outside), ...
    "sixgr:phy:ia:RAROutsideResponseWindow");
end

