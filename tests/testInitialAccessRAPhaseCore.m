function testRARNTIArithmetic(testCase)
root = localVectorRoot();
input = readtable(fullfile(root, "ra_rnti_test_vectors.csv"), ...
    "TextType", "string", "VariableNamingRule", "preserve");
expectedPath = fullfile(root, "expected_ra_rnti.csv");
expectedOptions = delimitedTextImportOptions( ...
    "NumVariables", 4, ...
    "Delimiter", ",", ...
    "VariableNames", ...
        ["CaseID","ExpectedRARNTI","Formula","ExpectedStatus"], ...
    "VariableTypes", ["string","double","string","string"], ...
    "DataLines", [2 Inf]);
expected = readtable(expectedPath, expectedOptions);
verifyEqual(testCase, height(input), 128);
verifyEqual(testCase, input.CaseID, expected.CaseID);
for ii = 1:height(input)
    actual = sixgr.phy.ra.computeRARNTI( ...
        "SymbolIndex", double(input.s_id(ii)), ...
        "SlotIndex", double(input.t_id(ii)), ...
        "FrequencyIndex", double(input.f_id(ii)), ...
        "ULCarrierId", double(input.ul_carrier_id(ii)));
    verifyEqual(testCase, actual, double(expected.ExpectedRARNTI(ii)), ...
        sprintf("RA-RNTI vector %s mismatched.", input.CaseID(ii)));
end
localVerifyError(testCase, @() sixgr.phy.ra.computeRARNTI( ...
    "SymbolIndex", 14), ...
    "sixgr:phy:ia:InvalidRARNTICoordinates");
end

