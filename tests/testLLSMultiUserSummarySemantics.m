function ok = testLLSMultiUserSummarySemantics()
%TESTLLSMULTIUSERSUMMARYSEMANTICS Keep user-summary validity separate from strict all-success outcomes.

passFailT = table( ...
    [1; 1], ...
    [11; 11], ...
    ["PASS"; "FAIL"], ...
    [1; 0], ...
    [false; false], ...
    [12.5; 0.0], ...
    'VariableNames', {'UEIndex','RNTI','Status','CRCPass','Crash','Goodput_Mbps'});

sem = sixgr.truth.deriveUserSummarySemantics(passFailT);
assert(logical(sem.SummaryRowValid), "Observed runtime rows must produce a valid user summary row.");
assert(logical(sem.RuntimeDataPresent), "Observed runtime rows must mark runtime data as present.");
assert(logical(sem.UserHadAnySuccessfulTx) && logical(sem.UserHadAnySuccessfulRx), ...
    "Mixed pass/fail runtime rows must preserve that the user had at least one successful transfer.");
assert(logical(sem.PartialSuccess), ...
    "Mixed pass/fail runtime rows must export partial-success semantics.");
assert(~logical(sem.AllObservedRowsSuccessful), ...
    "Mixed pass/fail runtime rows must not claim all observed rows were successful.");
assert(strcmpi(char(string(sem.SummaryStatus)), "partial_success"), ...
    "Mixed pass/fail runtime rows must export partial_success summary status.");
assert(logical(sem.Ok), ...
    "Compatibility Ok must follow summary-row validity instead of strict all-success.");
assert(strcmp(char(string(sem.OkDefinition)), "compatibility_alias_of_summary_row_valid"), ...
    "Compatibility Ok definition must disclose its new summary-row-valid meaning.");

failT = table( ...
    [2; 2], ...
    [12; 12], ...
    ["FAIL"; "CRASH"], ...
    [0; 0], ...
    [false; true], ...
    [0.0; 0.0], ...
    'VariableNames', {'UEIndex','RNTI','Status','CRCPass','Crash','Goodput_Mbps'});
semFail = sixgr.truth.deriveUserSummarySemantics(failT);
assert(logical(semFail.SummaryRowValid) && logical(semFail.RuntimeDataPresent), ...
    "All-failed runtime rows must still export a valid summary row with runtime data present.");
assert(~logical(semFail.UserHadAnySuccessfulTx) && ~logical(semFail.UserHadAnySuccessfulRx), ...
    "All-failed runtime rows must not claim any successful transfers.");
assert(~logical(semFail.PartialSuccess) && ~logical(semFail.AllObservedRowsSuccessful), ...
    "All-failed runtime rows must stay distinct from partial-success and all-success summaries.");
assert(strcmpi(char(string(semFail.SummaryStatus)), "all_failed"), ...
    "All-failed runtime rows must export all_failed summary status.");

emptySem = sixgr.truth.deriveUserSummarySemantics(table());
assert(~logical(emptySem.SummaryRowValid) && ~logical(emptySem.RuntimeDataPresent) && ~logical(emptySem.Ok), ...
    "Missing runtime data must not be mislabeled as a valid or successful user summary row.");
assert(strcmpi(char(string(emptySem.SummaryStatus)), "no_runtime_data"), ...
    "Missing runtime data must export no_runtime_data summary status.");

ok = true;
end
