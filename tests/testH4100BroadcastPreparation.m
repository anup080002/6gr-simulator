function ok = testH4100BroadcastPreparation()
%TESTH4100BROADCASTPREPARATION Full H4 broadcast and compact EPRE evidence.

setup6GRSimToolkit("Verbose",false);
scenario=sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    "simulator","configs","scenarios", ...
    "h4_100_cdlc100_connected_impaired_40db_gate.yaml"));
cfg=sixgr.lls6g.buildInternalConfig(scenario, ...
    fullfile(tempdir,"h4_100_broadcast_preparation"));
prepared=sixgr.link.prepareCellSearchBroadcast(cfg,true);

assert(prepared.SampleRateHz==122.88e6 && ...
    size(prepared.TransmitSamples,2)==64 && prepared.NumSamples>0, ...
    "H4 broadcast preparation must retain the full physical waveform contract.");
assert(double(cfg.phy.mib.pdcchConfigSIB1)==4 && ...
    double(prepared.Tx.SIB1AbsoluteSlot)==10 && ...
    double(sixgr.util.structGet(cfg,"phy.sib1.ssbObservationSubframes",NaN))==7 && ...
    double(prepared.NumSamples)==round(7e-3*prepared.SampleRateHz), ...
    ["The H4 first acquisition capture must contain its four-beam Case-B " ...
    "burst and independently resolved DL-capable slot-10:13 Type-0/SIB1 " ...
    "occasion without processing later periodic SS bursts."]);
assert(cfg.phy.sib1.transmissionScope=="all_active_ssb_occasions" && ...
    isequal(prepared.Tx.SIB1TransmitSSBIndices0Based,0:3) && ...
    isequal([prepared.Tx.SIB1Transmissions.SIB1AbsoluteSlot],10:13), ...
    "Every selectable H4 SSB beam needs its actual cell-authored SI occasion.");
assert(string(cfg.frequency.band_name)=="n77", ...
    "The H4 profile must signal concrete band n77, not parse a study label as n4.");
frame=sixgr.phy.FrameStructureEngine(cfg,"FrameCoreOnly",true);
sib1Partition=frame.SlotPartition(double(prepared.Tx.SIB1AbsoluteSlot));
assert(sib1Partition.AllowDL && ~sib1Partition.AllowUL, ...
    "The first H4 SI occasion must occupy fixed-DL slot 10.");
for si=prepared.Tx.SIB1Transmissions
    assert(frame.IsDLAllocation(si.SIB1AbsoluteSlot,[2 7]), ...
        "Every SI data allocation must fit entirely in DL symbols, including special slot 13.");
    assert(numel(si.DCI.Bits)==37 && isequal(si.PDSCH.PRBSet,126:149), ...
        "H4 SI must use the 24-PRB CORESET0 DCI and actual carrier-frequency mapping.");
end
plan=sixgr.phy.frame.CommonDLResourcePlan(cfg);
plan.validateSIB1References();
ue=struct('UEID',1,'RNTI',1,'ServingCell',1,'PUCCHCell',1, ...
    'ComponentCarrier',cfg.phy.frame.DefaultIdentity.ScheduledCCID, ...
    'ActiveULBWP',cfg.phy.frame.DefaultIdentity.ULBWPID);
calendar=sixgr.truth.configuredCSIReportCalendar(cfg,ue,19);
assert(height(calendar)==1 && calendar.ULResourceAvailable && ...
    calendar.CSIReferenceSlot>=cfg.phy.csirs.offset_slots+1 && ...
    cfg.phy.csirs.offset_slots==5 && cfg.phy.csi.reportOffsetSlots==18, ...
    "Relocating CSI-RS around SI must preserve the causal eight-resource CSI reporting window.");
bad=cfg;
bad.phy.csirs.offset_slots=12;
caught=false;
try
    conflicting=sixgr.phy.frame.CommonDLResourcePlan(bad);
    conflicting.validateSIB1References();
catch ME
    caught=strcmp(ME.identifier,"sixgr:phy:frame:SIB1CSIRSCollision");
end
assert(caught,"Full-band CSI-RS must not overwrite beam-2 common SI.");
bad=cfg;
bad.initial_access.sib1.pdsch.num_symbols=12;
bad.phy.sib1.pdsch=bad.initial_access.sib1.pdsch;
caught=false;
try
    sixgr.phy.frame.CommonDLResourcePlan(bad);
catch ME
    caught=strcmp(ME.identifier,"sixgr:phy:broadcast:SIB1SymbolsNotDLCapable");
end
assert(caught,"The old 12-symbol data allocation must remain illegal for beam 3's special slot.");
bad=cfg;
bad=sixgr.util.structSet(bad,"phy.mib.pdcchConfigSIB1",2);
caught=false;
try
    sixgr.phy.broadcast.resolveSIB1ControlOccasion( ...
        sixgr.phy.grid.makeCarrier(bad),bad);
catch ME
    caught=strcmp(ME.identifier, ...
        "sixgr:phy:broadcast:Type0OccasionNotDLCapable");
end
assert(caught, ...
    "The inherited slot-4 Type-0 occasion must fail closed against the installed TDD map.");
activeSSB=double(sixgr.util.structGet(cfg, ...
    "phy.ssb.activeCandidateIndices0Based",[]));
assert(isequal(activeSSB(:).',0:3), ...
    "H4 initial acquisition must execute exactly the four configured SSB candidates.");
assert(string(prepared.TxInfo.PowerNormalizationGridSource)== ...
    "exact_producer_ssb_pbch_sib1_active_port_grids", ...
    "H4 fixed-EPRE normalization must use exact producer grids, not a reconstructed or proxy grid.");
grid=prepared.TxInfo.PortGrid;
symbols=prepared.TxInfo.PortGridAbsoluteSymbolIndices;
assert(size(grid,1)==12*273 && size(grid,2)==numel(symbols) && ...
    size(grid,3)==64 && all(isfinite(grid),"all") && ...
    all(any(grid~=0,[1 3])), ...
    "The compact normalization grid must retain every active 64-element broadcast symbol.");
assert(prepared.PowerContext.FixedSNRNormalizedReference && ...
    string(prepared.PowerContext.PowerNormalizationPolicy)== ...
        "unit_occupied_re_fixed_esn0" && ...
    ~prepared.PowerContext.PhysicalDevicePowerClaim && ...
    prepared.PowerContext.PAEnabled && ...
    prepared.PowerContext.PAExecutionDeferred && ...
    string(prepared.PowerContext.PAReferenceDomain)== ...
        "normalized_complex_baseband_full_scale" && ...
    isnan(prepared.PowerContext.FullBWPActivityFactor) && ...
    abs(prepared.PowerContext.PowerClosureError_dB)<1e-9, ...
    "The broadcast must retain normalized fixed-SNR authority and defer its normalized PA.");

ok=true;
disp("H4_100_BROADCAST_PREPARATION_PASS");
end
