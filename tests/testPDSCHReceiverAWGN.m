function ok = testPDSCHReceiverAWGN()
%TESTPDSCHRECEIVERAWGN High-SNR explicit waveform reception.

setup6GRSimToolkit("Verbose", false);
rng(9102,"twister");
fixture = StrictPDSCHChainFixture.create(2);
tx = sixgr.pdsch.PDSCHTransmitter( ...
    fixture.TransportBlocks, fixture.Assignment, fixture.ResourcePlan, ...
    fixture.Carrier, fixture.ReferenceConfig, ...
    "PrecoderBundle", fixture.PrecoderBundle);
signalPower = mean(abs(tx.Waveform(:)).^2);
timeNoiseVariance = signalPower / 10^(35/10);
noise = sqrt(timeNoiseVariance/2) * ...
    complex(randn(size(tx.Waveform)),randn(size(tx.Waveform)));
receiver = fixture.ReceiverConfig;
receiver.NoiseVariance = timeNoiseVariance ...
    * double(tx.OFDMInfo.SampleToGridNoiseVarianceGain);
rx = sixgr.pdsch.PDSCHReceiver( ...
    tx.Waveform + noise, fixture.Assignment, fixture.ResourcePlan, ...
    fixture.Carrier, fixture.ReferenceConfig, receiver, ...
    "CodingPlans", tx.CodingPlans, ...
    "PrecoderBundle", fixture.PrecoderBundle);

assert(rx.CRCPass && isequal(rx.TransportBlocks{1},fixture.TransportBlocks{1}), ...
    "High-SNR AWGN strict receiver did not recover the exact TB.");
assert(all(isfinite(rx.DescrambledLLR{1})) ...
    && all(isfinite(rx.Metrics.MeasuredPostEqualizationSINRdBPerLayer)), ...
    "AWGN receiver produced nonfinite LLR/SINR metrics.");
assert(rx.Metrics.BLERPerCodeword == 0, ...
    "Successful AWGN decode must report BLER zero.");
fprintf("PDSCH strict RX AWGN: CRC pass, estimated noise %.3g\n", ...
    rx.EstimatedNoiseVariance);
ok = true;
end
