function seeds=validatePUCCHDetectorCampaignPolicy(v,p)
% Preregistered campaign constraints, not evidence of RF independence.
required=sort(["schema_version","research_class","stage","profile_id", ...
    "episode_policy_path","episodes","seed_base","seed_stride","family_alpha", ...
    "event_error_limit","development_seeds","development_history_complete", ...
    "execution_batch_episodes"]);
assert(isstruct(v) && isscalar(v) && ...
    isequal(sort(string(fieldnames(v))).',required), ...
    'test:CampaignPolicy','Missing or unknown detector campaign policy fields.');
assert(isequal(v.schema_version,1) && string(v.stage)=="held_out_campaign" && ...
    string(v.research_class)=="optional_research_experiment", ...
    'test:CampaignPolicy','Expected schema 1 held_out_campaign experiment.');
validatePUCCHDetectorPilotPolicy(p);
validateattributes(v.episodes,{'numeric'},{'scalar','integer','finite','positive','<=',2^32});
validateattributes(v.seed_base,{'numeric'},{'scalar','integer','finite','nonnegative','<=',2^32-1});
validateattributes(v.seed_stride,{'numeric'},{'scalar','integer','finite','positive','<=',2^32-1});
validateattributes(v.execution_batch_episodes,{'numeric'}, ...
    {'scalar','integer','finite','positive','<=',v.episodes});
assert(v.episodes>=p.qualification_episodes_per_case && ...
    v.family_alpha==p.family_alpha && v.event_error_limit==p.event_error_limit, ...
    'test:CampaignGates','Episode count cannot shrink and original statistical gates must be retained.');
assert(islogical(v.development_history_complete) && isscalar(v.development_history_complete), ...
    'test:CampaignHistory','History completeness must be an explicit logical declaration.');
validateattributes(v.development_seeds,{'numeric'}, ...
    {'vector','nonempty','integer','finite','nonnegative','<=',2^32-1});
assert(numel(unique(v.development_seeds))==numel(v.development_seeds), ...
    'test:CampaignHistory','Duplicate development seeds are not distinct history records.');
assert(v.episodes-1<=floor((2^32-1-v.seed_base)/v.seed_stride), ...
    'test:CampaignSeeds','Held-out seed schedule overflows uint32.');
% Reject overlap arithmetically before allocating the schedule.
reserved=double(v.development_seeds(:));
pilotSeeds=double(p.seed_base)+(0:double(p.episodes)-1)*double(p.seed_stride);
assert(all(ismember(pilotSeeds,reserved)), ...
    'test:CampaignHistory','Every declared development pilot seed must be excluded.');
offset=reserved-v.seed_base;
assert(~any(offset>=0 & mod(offset,v.seed_stride)==0 & offset/v.seed_stride<v.episodes), ...
    'test:CampaignSeeds','Held-out schedule overlaps development seeds.');
seeds=double(v.seed_base)+(0:double(v.episodes)-1)*double(v.seed_stride);
end
