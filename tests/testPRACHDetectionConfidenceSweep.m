function ok = testPRACHDetectionConfidenceSweep()
%TESTPRACHDETECTIONCONFIDENCESWEEP Confidence and SNR coverage contract.

setup6GRSimToolkit("Verbose", false);
b = prachStrictAnchorResult();
T = b.Result.ArtifactTables.prach_missed_detection_sweep;

required = ["NumTrials","NumDetected","NumMissed","MissedDetectionCILower", ...
    "MissedDetectionCIUpper","DetectionCILower","DetectionCIUpper", ...
    "QualificationRequired","StatisticalQualification","StoppingReason", ...
    "DeterministicSeedSet","EvidenceUnit"];
assert(all(ismember(required,string(T.Properties.VariableNames))), ...
    "PRACH detection evidence must carry counts, intervals, status and seed provenance.");
assert(isequal(sort(double(T.SNRdB(:))),sort(double(b.Config.SNRSweep_dB(:)))), ...
    "Every requested PRACH SNR must have an explicit detection row.");
assert(all(double(T.NumDetected)+double(T.NumMissed) == double(T.NumTrials)), ...
    "Detection event counts must reconcile exactly to the waveform trial count.");
assert(all(double(T.MissedDetectionCILower) <= double(T.MissedDetectionProbability)) && ...
    all(double(T.MissedDetectionCIUpper) >= double(T.MissedDetectionProbability)), ...
    "Exact missed-detection intervals must contain their point estimates.");
assert(all(string(T.StatisticalQualification(~T.QualificationRequired)) == "NOT_APPLICABLE"), ...
    "Characterization-only SNRs must not make qualification claims.");
requiredRows = logical(T.QualificationRequired);
assert(any(requiredRows) && all(string(T.StatisticalQualification(requiredRows)) == "NOT_EVALUATED"), ...
    "The two-trial required mini-anchor point must remain statistically unresolved.");
assert(all(strlength(string(T.DeterministicSeedSet)) > 0), ...
    "Every detection row must identify its deterministic seed set.");
ok = true;
end
