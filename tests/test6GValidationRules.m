function ok = test6GValidationRules()
%TEST6GVALIDATIONRULES Validate explicit 6G candidate/stress gating rules.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

localExpectInvalid(tmp, "bad_multilayer_dfts", struct( ...
    "meta", struct("research_class", "study_item_candidate"), ...
    "waveform", struct("ul_waveform", "DFT-S-OFDM", "transform_precoding_enabled", true), ...
    "mimo", struct("n_layers", 2), ...
    "pusch", struct("layer_count", 2)), "MultiLayerDFTSOFDMCandidateRequired");

localExpectInvalid(tmp, "bad_nonqpsk_pdcch", struct( ...
    "pdcch", struct("modulation", "16QAM")), ...
    "NonQPSKPDCCHCandidateRequired");

localExpectInvalid(tmp, "bad_1024qam_visibility", struct( ...
    "modulation", struct("dl_modulation_order", 10, "ul_modulation_order", 10), ...
    "modulation_and_mapping", struct("high_order_modulation_stress_enabled", true)), ...
    "HighOrderModulationImpairmentVisibilityRequired");

localExpectInvalid(tmp, "bad_strict_modulation_mcs_pair", struct( ...
    "meta", struct("tags", {{"truth","no-proxy"}}), ...
    "modulation", struct("dl_modulation_order", 4, "ul_modulation_order", 4, ...
        "mcs_table", "qam64_table1", "dl_mcs_index", 4, "ul_mcs_index", 4)), ...
    "ModulationMCSConsistencyRequired");

localExpectInvalid(tmp, "bad_4096qam", struct( ...
    "modulation", struct("dl_modulation_order", 12, "ul_modulation_order", 12), ...
    "modulation_and_mapping", struct("high_order_modulation_stress_enabled", true, "qam4096_candidate_enabled", true), ...
    "output_control", struct("impairment_visibility", "full")), ...
    "QAM4096HardwareImpairmentRequired");

localExpectInvalid(tmp, "bad_jscc", struct( ...
    "ai_ml", struct("enabled", true, "mode", "online_inference", "use_case", "csi_compression_reconstruction", ...
        "model_path", "simulator/configs/models/csi_autoencoder_descriptor.json", "model_id", "jscc_bad", ...
        "model_version", "1.0", "descriptor_type", "benchmark_descriptor", "csi_feedback_mode", "jscc", ...
        "baseline_pairing", "non_ai_baseline"), ...
    "csi_acquisition_and_reporting", struct("jscc_mode", true, "jscm_mode", false, ...
        "crc_attached_mode", true, "crc_free_mode", false, "multiplexing_with_uci_policy", "baseline")), ...
    "JSCCJSCMRFPAPRConfigRequired");

localExpectInvalid(tmp, "bad_dci_switching", struct( ...
    "bandwidth_operation", struct("dci_based_switching_enabled", true)), ...
    "DCISwitchingReliabilityPolicyRequired");

localExpectInvalid(tmp, "bad_joint_csi", struct( ...
    "reference_signals", struct("csi_acquisition_mode", "joint_dl_ul"), ...
    "csi_acquisition_and_reporting", struct("joint_dl_ul_csi_enabled", true)), ...
    "JointCSIPortMappingRequired");

localExpectInvalid(tmp, "bad_full_duplex", struct( ...
    "deployment_topology", struct("full_duplex_flag", true)), ...
    "FullDuplexSIPathRequired");

localExpectInvalid(tmp, "bad_tracking_rs_trp", struct( ...
    "mimo", struct("trp_count", 2), ...
    "reference_signals", struct("tracking_rs_enabled", true)), ...
    "TrackingRSMultiTRPAssumptionRequired");

localExpectInvalid(tmp, "bad_minimum_artifacts", struct( ...
    "run_control", struct("save_intermediate", false), ...
    "output_control", struct("save_resolved_config", false, "artifact_formats", {"png"}, "save_report", false)), ...
    "MinimumArtifactsRequired");

localExpectInvalid(tmp, "bad_ai_baseline", struct( ...
    "ai_ml", struct("enabled", true, "mode", "online_inference", "use_case", "demodulation", ...
        "model_path", "simulator/configs/models/detector_selector_descriptor.json", "model_id", "ai_bad", ...
        "model_version", "1.0", "descriptor_type", "benchmark_descriptor", "baseline_pairing", "none")), ...
    "AINeedsBaselineComparator");

localExpectValid(tmp, "good_joint_csi", struct( ...
    "reference_signals", struct("csi_acquisition_mode", "joint_dl_ul"), ...
    "csi_acquisition_and_reporting", struct("joint_dl_ul_csi_enabled", true, ...
        "joint_port_mapping_policy", "shared_port_map", "joint_timeline_policy", "aligned_joint_timeline")));

localExpectValid(tmp, "good_4096qam", struct( ...
    "modulation", struct("dl_modulation_order", 12, "ul_modulation_order", 12), ...
    "modulation_and_mapping", struct("high_order_modulation_stress_enabled", true, "qam4096_candidate_enabled", true), ...
    "output_control", struct("impairment_visibility", "full"), ...
    "power_and_rf_frontend", struct("pa_nonlinearity_model", "rapp_baseline"), ...
    "sweeps_and_matrix", struct("snr_sweep", struct("enabled", true, "values_db", [30, 40, 50]))));

ok = true;
end

function localExpectInvalid(tmp, name, patch, expectedID)
cfg = localBaseScenarioStruct(name);
cfg = sixgr.util.mergeStruct(cfg, patch);
path = localWriteConfig(tmp, name, cfg);
threw = false;
try
    sixgr.lls6g.config.loadScenarioConfig(path);
catch ME
    threw = contains(string(ME.identifier), string(expectedID));
end
assert(threw, "Expected %s to fail with %s.", name, expectedID);
end

function localExpectValid(tmp, name, patch)
cfg = localBaseScenarioStruct(name);
cfg = sixgr.util.mergeStruct(cfg, patch);
path = localWriteConfig(tmp, name, cfg);
scfg = sixgr.lls6g.config.loadScenarioConfig(path);
assert(strlength(string(scfg.ScenarioID)) > 0, "Scenario %s should load successfully.", name);
end

function path = localWriteConfig(tmp, name, cfg)
cfgDir = char(tempname());
mkdir(cfgDir);
path = char(fullfile(char(cfgDir), [char(name) '.yaml']));
sixgr.util.jsonWrite(path, cfg);
end

function cfg = localBaseScenarioStruct(name)
cfg = struct();
cfg.inherits = {fullfile(pwd, "simulator", "configs", "defaults", "global.yaml")};
cfg.meta = struct( ...
    "scenario_id", char(name), ...
    "description", char(name), ...
    "version", "1.0", ...
    "owner", "test", ...
    "maturity_tag", "smoke");
end
