function ok=testLLSCSIMetricIntegrity()
% Bounded production-export regression. Explicit input fixtures are not PHY
% or detector-performance evidence. No waveform campaign/testAll is started.
setup6GRSimToolkit('Verbose',false);
[fixtureOK,reports]=testCSIReportDeliveryEvidence();
assert(fixtureOK);
root=fullfile(pwd,'results','validation','lls_csi_metric_integrity', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
layout=sixgr.report.resultLayout(root);
sixgr.util.ensureFolder(layout.AirInterfaceCSVDir);
scfg=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_tdd_5mhz_rank2_4tx2rx_awgn_0db.yaml');
cfg=sixgr.lls6g.buildInternalConfig(scfg,root);
manifest=struct('CodeVersion',"test",'CodeDetail',"declared_export_fixture_no_PHY_execution", ...
    'RandomSeed',1,'GeneratedUTC',"test",'RunnerProfile',"test", ...
    'RunCompletion',"completed",'DeterministicMode',"test");
% These unrelated scalars previously produced five plausible-looking false
% accuracy results and an unconditional zero DMRS-versus-CSI-RS delta.
trial=table(1,1,20,11,20,3,4,4,3,1,1,1,20,0,.01,0,0,-20, ...
    'VariableNames',{'Slot','UEIndex','ConfiguredSNR_dB','WidebandCQI', ...
    'PostEqSINR_dB','PMI','BestBeamIndex','SelectedBeamIndex','ConfiguredPMI', ...
    'RankIndicator','RankEstimate','Layers','ReceiverHestSINR_dB', ...
    'ChannelGain_dB','NoiseVariance','SelectedBeamGain_dB','BestBeamGain_dB','NMSE_dB'});
trial.Status="PASS";
sixgr.util.csvWriteTable(fullfile(layout.AirInterfaceCSVDir,'dl_pdsch_trials.csv'),trial, ...
    'PreserveSchema',true,'RoundTripNumericText',true);
sixgr.util.csvWriteTable(fullfile(layout.AirInterfaceCSVDir,'received_csi_reports.csv'),reports, ...
    'PreserveSchema',true,'RoundTripNumericText',true);
out=publish(); rows=out.CategoryRows;
checkIndependent(rows);
for field=["cqi","pmi","ri","cri"]
    selected=rows(rows.MetricKey==field+"_field_delivery" & ...
        rows.Statistic=="decoded_field_agrees",:);
    assert(height(selected)==2 && all(selected.ValueNumeric==1) && ...
        numel(unique(selected.Entity))==2 && all(selected.CountsTowardCoverage), ...
        'Exact CSI delivery must stay separate for the two point/seed/execution contexts.');
    assert(all(contains(selected.Notes,"not CSI selection optimality")) && ...
        all(contains(selected.Entity,"@ExecutionID=")) && ...
        all(contains(selected.Entity,"@SweepPointIndex=")));
end
bits=rows(rows.MetricKey=="csi_bit_delivery" & rows.Statistic=="BitErrorCount",:);
assert(height(bits)==2 && all(bits.ValueNumeric==0));
verified=rows(rows.Statistic=="scheduler_delivery_projection_verified",:);
assert(height(verified)==8 && all(verified.ValueNumeric==1) && ...
    ~any(rows.Statistic=="scheduler_delivery_observed"), ...
    'Combined delivery and projection evidence must not be labelled as the delivery event alone.');
saved=sixgr.util.csvReadTable(out.DetailCSV,'TextType','string');
checkIndependent(saved);
audit=sixgr.util.csvReadTable(fullfile(layout.ReportCSVDir, ...
    'csi_report_delivery_observations.csv'),'TextType','string');
assert(height(audit)==2 && all(audit.EmissionVerified) && all(audit.PopulationScopeComplete));
% A corruption or a source claim alone cannot become available delivery.
reports.CSIDeliveryAuditJSON(:)="";
sixgr.util.csvWriteTable(fullfile(layout.AirInterfaceCSVDir,'received_csi_reports.csv'),reports, ...
    'PreserveSchema',true,'RoundTripNumericText',true);
out=publish(); checkIndependent(out.CategoryRows);
delivery=out.CategoryRows(endsWith(out.CategoryRows.MetricKey,"_field_delivery") | ...
    out.CategoryRows.MetricKey=="csi_bit_delivery",:);
assert(~any(delivery.CountsTowardCoverage) && ~any(isfinite(delivery.ValueNumeric)), ...
    'Absent exact TX/decoded operands must not fall back to recommendation or grant fields.');
fprintf('LLS_CSI_METRIC_INTEGRITY_PASS exact_delivery_export=1 fabricated_references_removed=1 export_fixture_only=1 evidence=%s\n',root);
ok=true;

    function output=publish()
        output=sixgr.truth.exportLLSReportingBundle(root,scfg,cfg,struct('Ok',false), ...
            manifest,struct('StartedUTC',"test",'ElapsedSeconds',1),struct());
    end
end

function checkIndependent(rows)
for key=["cqi_accuracy","pmi_accuracy","ri_accuracy","l1_sinr_accuracy", ...
        "rsrp_accuracy","dmrs_vs_csirs_comparison"]
    selected=rows(rows.MetricKey==key,:);
    assert(~isempty(selected) && ~any(selected.CountsTowardCoverage) && ...
        all(selected.Availability=="not_available") && ~any(isfinite(selected.ValueNumeric)), ...
        'Missing independent evidence must not generate %s from unrelated fields.',key);
end
assert(~any(rows.Statistic=="shared_estimator_delta_db"));
end
