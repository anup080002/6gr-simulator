function ok = testH4100SharedBroadcastReception()
%TESTH4100SHAREDBROADCASTRECEPTION Receive the H4 four-beam burst on its shared RF clock.
%
% The configured active Case-B candidates 0:3 and the Type-0/SIB1
% occasion are all contained in subframe zero.  This focused regression
% therefore executes the complete physical observation in two 30-kHz
% slots without launching the 200-slot scenario.

setup6GRSimToolkit("Verbose",false);
testRoot = tempname;
mkdir(testRoot);
cleanup = onCleanup(@()localCleanup(testRoot)); %#ok<NASGU>
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    "simulator","configs","scenarios", ...
    "h4_100_cdlc100_connected_impaired_40db_gate.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scenario, ...
    testRoot);
cfg = sixgr.util.structSet(cfg,"run.rootRunFolder",testRoot);

multiUser = struct("Enabled",true,"NumUsers",1,"RNTIStart",1, ...
    "ExecutionModel","slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfg,tempdir,multiUser,struct(),2);
state.CurrentSlot = 1;
state.CurrentServingIdx(:) = 1;
[state,stream] = sixgr.truth.CoupledWaveformStream.initialize( ...
    state,cfg,{cfg});
[dl,~] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
    cfg,state,1,"DL");

prototype = sixgr.link.runCellSearch_MIB_SIB1(dl, ...
    "PrepareOnly",true,"UseRuntimeChannel",true,"RuntimeSlot",0, ...
    "NumSubframes",1);
assert(isfield(prototype,"PreparedBroadcast"), ...
    "H4 shared broadcast preparation failed: %s", ...
    string(sixgr.util.structGet(prototype,"FailureReason","")));
txEvidence = prototype.SSBTxEvidence;
assert(double(txEvidence.ConfiguredBeamCount)==4 && ...
    double(txEvidence.ExecutedBeamCount)==4 && ...
    numel(txEvidence.PrecoderMatrixSHA256)==4 && ...
    numel(txEvidence.PrecoderIDs)==4, ...
    "Broadcast evidence must retain exactly the four executed beams, not the eight-entry Lmax codebook.");
for ssbIndex = 0:3
    assert(strlength(sixgr.truth.resolveSSBPrecoderHash( ...
        txEvidence,ssbIndex))==64, ...
        "Executed SSB %d must own one exact physical precoder hash.",ssbIndex);
end
prepared = prototype.PreparedBroadcast;
assert(prepared.NumSamples == round(prepared.SampleRateHz*1e-3), ...
    "The focused H4 observation must occupy exactly subframe zero.");
assert(double(prepared.Tx.SIB1AbsoluteSlot)==0, ...
    "The focused observation must retain the TDD-legal slot-0 SIB1.");
active = double(sixgr.util.structGet(dl, ...
    "phy.ssb.activeCandidateIndices0Based",[]));
assert(isequal(active(:).',0:3), ...
    "The focused observation must retain all four active SSB candidates.");

context = struct("Config",dl,"Slot",1,"Frame",1,"RNTI",1, ...
    "ServingCell",1,"SNR",40,"Prototype",prototype, ...
    "TrackingOnly",false);
stream.queueDownlink("PBCH",1,prepared,context);
completed = struct("Kind",{},"UE",{},"Context",{},"Planes",{});
for slot = 1:2
    state.CurrentSlot = slot;
    [state,items] = stream.advanceSlot(state,cfg);
    completed = [completed,items]; %#ok<AGROW>
end
hit = find(string({completed.Kind})=="PBCH");
assert(isscalar(hit), ...
    "Exactly one complete H4 PBCH observation must finish after subframe zero.");
item = completed(hit);
[~,pre,tx,replay,post] = sixgr.truth.sharedObservationEvidence(item.Planes);
channelState = stream.channelState(1,"DL");
receiverPrototype = prototype;
receiverPrototype.RuntimeChannelReplay = replay;
receiverPrototype.RuntimeDLChannelState = channelState;
receiverPrototype.RuntimeChannelStateUsed = true;
receiverPrototype.PowerContext = prepared.PowerContext;
options = struct("UseRuntimeChannel",true,"RuntimeSlot",0, ...
    "CandidateSSBIndices",active,"SSBIndex",[], ...
    "WriteArtifacts",false,"RunFolder","", ...
    "RunId","h4_100_shared_broadcast_reception", ...
    "PhysicalMeasurementObservation",pre, ...
    "TransmitObservation",tx);
received = sixgr.link.completeCellSearchBroadcast( ...
    prepared,post,receiverPrototype,options,tic);

rows = repmat(localRow(),numel(received.CandidateResults),1);
for candidate = 1:numel(received.CandidateResults)
    result = received.CandidateResults{candidate};
    rows(candidate) = localRow(result);
end
evidence = struct2table(rows,"AsArray",true);
disp(evidence);
assert(height(evidence)==4 && isequal(double(evidence.SSBIndex(:)).',0:3), ...
    "The shared receiver must return one row for every active H4 SSB candidate.");
assert(all(evidence.PSSDetected & evidence.SSSDetected & ...
    evidence.NCellIDRecovered & evidence.BCHCrcPass & ...
    evidence.MIBDecoded & evidence.SIB1StrictOk), ...
    "Every H4 candidate must complete PSS/SSS/PBCH/MIB/SIB1: %s", ...
    strjoin(evidence.FailureReason," | "));
assert(all(evidence.StrictReceiverEvidenceOk) && ...
    all(isfinite(evidence.MeasuredTrialSINR_dB)), ...
    "H4 acquisition must retain strict measured receiver evidence.");

ok = true;
disp("H4_100_SHARED_BROADCAST_RECEPTION_PASS");
end

function row = localRow(result)
if nargin==0
    result = struct();
end
sib1 = sixgr.util.structGet(result,"SIB1",struct());
pbch = sixgr.util.structGet(result,"PBCH",struct());
row = struct( ...
    "SSBIndex",double(sixgr.util.structGet(result,"SSBIndex",NaN)), ...
    "PSSDetected",logical(sixgr.util.structGet(result,"PSSDetected",false)), ...
    "SSSDetected",logical(sixgr.util.structGet(result,"SSSDetected",false)), ...
    "NCellIDRecovered",logical(sixgr.util.structGet(result,"NCellIDRecovered",false)), ...
    "BCHCrcPass",logical(sixgr.util.structGet(sib1,"BCHCrcPass",false)), ...
    "MIBDecoded",logical(sixgr.util.structGet(sib1,"MIBDecoded",false)), ...
    "SIB1StrictOk",logical(sixgr.util.structGet(sib1,"StrictOk",false)), ...
    "StrictReceiverEvidenceOk",logical(sixgr.util.structGet( ...
        pbch,"StrictReceiverEvidenceOk",false)), ...
    "MeasuredTrialSINR_dB",double(sixgr.util.structGet( ...
        result,"MeasuredTrialSINR_dB",NaN)), ...
    "FailureReason",string(sixgr.util.structGet(result,"FailureReason","")));
end

function localCleanup(path)
if isfolder(path)
    rmdir(path,"s");
end
end
