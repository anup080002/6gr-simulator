function ok = testLLSMeasurementSidecarIntegrity()
%TESTLLSMEASUREMENTSIDECARINTEGRITY Keep measurements separate from labels.

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

layout = sixgr.report.resultLayout(tmp);
sixgr.util.ensureFolder(layout.AirInterfaceCSVDir);
sixgr.util.ensureFolder(layout.ReportCSVDir);

rawT = table( ...
    ["DL"; "DL"], [1; 1], [3; 4], [101; 102], ...
    [12.5; NaN], [true; false], ...
    [11.0; 9.5], [NaN; NaN], [true; true], ...
    ["PASS"; "FAIL"], ...
    ["available_runtime_abstraction"; "unavailable"], ...
    ["system_level_scheduler_grant_trace"; "proxy_debug_only"], ...
    'VariableNames', {'Direction','Frame','Slot','UEID', ...
    'PostEqSINR_dB','CRCPass','SystemLevelSINR_dB', ...
    'DecoderTruthProxySINR_dB','ControlObservationAvailable', ...
    'Status','ValueStatus','ValueSource'});
% A real DL trial can contain a long, pipe-packed decoder vector. It is a
% single CSV cell, not another delimiter domain.
packedParity = join(repmat("0", 1, 5000), "|");
rawT.MeasuredLDPCParityCheckVector = repmat(packedParity, height(rawT), 1);
rawT.Msg4PDUHex=["000000000123";"000000000456"];
rawT.PayloadBitVector=["000000000001";"000000000010"];
sixgr.util.csvWriteTable(fullfile(layout.AirInterfaceCSVDir, "dl_pdsch_trials.csv"), rawT);

bindingT = table( ...
    ["frame.scs_khz"; "frequency.bandwidth_hz"], ...
    ["Carrier_Numerology_Grid"; "Carrier_Numerology_Grid"], ...
    ["30"; ""], ["30"; "100000000"], ...
    ["measured_runtime_evidence_published"; "evidence_not_applicable"], ...
    'VariableNames', {'ParameterId','FeatureFamily','RuntimeAppliedEvidenceValue', ...
    'RuntimeMeasuredEvidenceValue','RuntimeMeasuredStatus'});
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, "parameter_binding_matrix.csv"), bindingT);

% Received CSI and UE-side CSI-RS measurements are different source tables.
% Keep both clocks and sweep identities without copying unreported SINR.
csi=table([1;2],[40;20],[34;34],[39;39],[39;39],[2;1],[9;5],[3;0], ...
    [NaN;NaN],[true;true],repmat("received_CSI_UCI",2,1), ...
    'VariableNames',{'SweepPointIndex','ConfiguredSNR_dB','SourceSlot', ...
    'DueSlot','DeliveredSlot','RI','CQI','CRI','SINR_dB','CSIUCIDecodeOk','SourceSignal'});
sixgr.util.csvWriteTable(fullfile(layout.AirInterfaceCSVDir, ...
    'received_csi_reports.csv'),csi,'PreserveSchema',true);
rs=table([1;2],[40;20],[26;26],[32.1;18.4], ...
    'VariableNames',{'SweepPointIndex','ConfiguredSNR_dB','Slot','ReferenceMeasuredSINR_dB'});
sixgr.util.csvWriteTable(fullfile(layout.AirInterfaceCSVDir,'csi_rs_trials.csv'),rs);

out = sixgr.truth.exportLLSMeasurementSidecars(tmp);
assert(logical(out.Ok), "Measurement-sidecar audit must pass for split measurement views.");
csiMeasured=readtable(fullfile(layout.ReportCSVDir,'measurements', ...
    'received_csi_measurements.csv'),'VariableNamingRule','preserve');
csiProvenance=readtable(fullfile(layout.ReportCSVDir,'provenance_sidecars', ...
    'received_csi_provenance.csv'),'VariableNamingRule','preserve');
rsMeasured=readtable(fullfile(layout.ReportCSVDir,'measurements', ...
    'csi_rs_measurements.csv'),'VariableNamingRule','preserve');
assert(isequal(csiMeasured.RI,csi.RI) && isequal(csiMeasured.CQI,csi.CQI));
assert(isequal(csiMeasured.CRI,csi.CRI), ...
    'Decoded CRI must be retained without substituting a PMI or activated TCI identity.');
assert(isequal(csiMeasured.SweepPointIndex,csi.SweepPointIndex) && ...
    isequal(csiProvenance.SweepPointIndex,csi.SweepPointIndex) && ...
    isequal(csiProvenance.DeliveredSlot,csi.DeliveredSlot));
assert(~ismember('SINR_dB',csiMeasured.Properties.VariableNames) || ...
    all(isnan(csiMeasured.SINR_dB)), ...
    'UE CSI-RS SINR is not a decoded CSI report field.');
assert(isequal(rsMeasured.ReferenceMeasuredSINR_dB,rs.ReferenceMeasuredSINR_dB));
dlAudit = out.Audit(string(out.Audit.MeasurementArtifact) == ...
    "reports/csv/measurements/dl_pdsch_measurements.csv", :);
assert(height(dlAudit) == 1 && logical(dlAudit.SchemaExpansionOk) && ...
    double(dlAudit.UnexpectedGeneratedVariableCount) == 0, ...
    "Measurement audit must fail closed on delimiter-driven Var* expansion.");

measurementPath = fullfile(layout.ReportCSVDir, "measurements", "dl_pdsch_measurements.csv");
provenancePath = fullfile(layout.ReportCSVDir, "provenance_sidecars", "dl_pdsch_provenance.csv");
tracePath = fullfile(layout.ReportCSVDir, "measurements", "parameter_binding_runtime_values.csv");
assert(exist(measurementPath, "file") == 2, "DL measurement view must be written.");
assert(exist(provenancePath, "file") == 2, "DL provenance sidecar must be written.");
assert(exist(tracePath, "file") == 2, "Parameter traceability value view must be written.");

measurementT = readtable(measurementPath, "Delimiter", ",", ...
    "VariableNamingRule", "preserve", "TextType", "string");
provenanceT = sixgr.util.csvReadTable(provenancePath,"TextType","string");
assert(isequal(provenanceT.Msg4PDUHex,rawT.Msg4PDUHex)&& ...
    isequal(provenanceT.PayloadBitVector,rawT.PayloadBitVector), ...
    'Measurement sidecars must retain original opaque bytes and leading zeroes.');
traceT = readtable(tracePath, "Delimiter", ",", ...
    "VariableNamingRule", "preserve", "TextType", "string");
manifestT = readtable(out.ManifestPath, "Delimiter", ",", ...
    "VariableNamingRule", "preserve", "TextType", "string");
dlManifest = manifestT(string(manifestT.MeasurementArtifact) == ...
    "reports/csv/measurements/dl_pdsch_measurements.csv", :);
assert(height(dlManifest) == 1 && ...
    double(dlManifest.MeasurementRows) == height(measurementT) && ...
    double(dlManifest.ProvenanceRows) == height(provenanceT) && ...
    double(dlManifest.MeasurementColumnCount) == width(measurementT) && ...
    double(dlManifest.ProvenanceColumnCount) == width(provenanceT), ...
    "Measurement-sidecar manifest must describe the exact persisted files after writer pruning.");

assert(all(ismember(["Direction","Frame","Slot","UEID","PostEqSINR_dB","CRCPass"], string(measurementT.Properties.VariableNames))), ...
    "Measurement view must preserve keys and measured numeric/boolean columns.");
assert(~any(ismember(["Status","ValueStatus","ValueSource"], string(measurementT.Properties.VariableNames))), ...
    "Measurement view must not carry status/source provenance columns.");
assert(width(measurementT) < 32 && ...
    ~any(startsWith(string(measurementT.Properties.VariableNames), "Var")), ...
    "Pipe-packed runtime vectors must not be misread as thousands of CSV columns.");
assert(ismember("MeasuredLDPCParityCheckVector", ...
    string(provenanceT.Properties.VariableNames)) && ...
    all(strlength(string(provenanceT.MeasuredLDPCParityCheckVector)) > 9000), ...
    "The exact decoder vector must remain one provenance-sidecar cell.");
assert(~any(ismember(["SystemLevelSINR_dB","DecoderTruthProxySINR_dB", ...
        "ControlObservationAvailable"], string(measurementT.Properties.VariableNames))), ...
    "Measurement view must not carry proxy/system-level/availability evidence columns.");
assert(~localTableContainsToken(measurementT, ["available_runtime_abstraction","unavailable","proxy"]), ...
    "Measurement view must not carry label/proxy/unavailable tokens.");
assert(all(ismember(["Status","ValueStatus","ValueSource", ...
        "SystemLevelSINR_dB","DecoderTruthProxySINR_dB", ...
        "ControlObservationAvailable"], string(provenanceT.Properties.VariableNames))) && ...
    localTableContainsToken(provenanceT, ["available_runtime_abstraction","unavailable","proxy"]), ...
    "Provenance sidecar must retain label/source diagnostics.");
assert(any(string(traceT.ParameterId) == "frame.scs_khz" & ...
    string(traceT.ValueKind) == "RuntimeAppliedEvidenceValue" & string(traceT.Value) == "30"), ...
    "Parameter traceability value view must preserve runtime-applied values without status columns.");

ok = true;
end

function tf = localTableContainsToken(T, tokens)
tf = false;
tokens = lower(string(tokens(:)));
vars = string(T.Properties.VariableNames);
for v = vars
    vals = lower(string(T.(char(v))));
    for token = tokens.'
        if any(contains(vals, token))
            tf = true;
            return;
        end
    end
end
end
