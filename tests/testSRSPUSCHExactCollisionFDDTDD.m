function ok = testSRSPUSCHExactCollisionFDDTDD()
%TESTSRSPUSCHEXACTCOLLISIONFDDTDD Shared exact RE arbitration for both duplexes.
%
% Duplex selection controls which slots can carry uplink.  It must not
% select a different collision algorithm.  In every legal UL occasion the
% same Toolbox-derived SRS and scheduled-PUSCH coordinates are compared.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
scenarioPaths = [ ...
    fullfile("simulator", "configs", "scenarios", ...
        "lls_causal_access_to_data_wiring.yaml"), ...
    fullfile("simulator", "configs", "scenarios", ...
        "lls_causal_access_to_data_wiring_tdd.yaml")];
expectedDuplex = ["FDD", "TDD"];

for profileIdx = 1:numel(scenarioPaths)
    scenario = sixgr.lls6g.config.loadScenarioConfig( ...
        scenarioPaths(profileIdx));
    cfg = sixgr.config.normalizeConfig( ...
        sixgr.lls6g.buildInternalConfig(scenario, string(tempname)));
    duplex = upper(string(sixgr.phy.frame.resolveDuplexMode(cfg)));
    assert(duplex == expectedDuplex(profileIdx));

    absoluteSlotOneBased = localFindLegalActiveSRSSlot(cfg);
    grant = localScheduledPUSCHGrant(cfg, absoluteSlotOneBased, ...
        double(cfg.phy.pusch.SymbolAllocation));
    collision = sixgr.phy.frame.resolveSRSPUSCHCollision( ...
        cfg, grant, absoluteSlotOneBased);

    assert(collision.Exact && ~collision.ApproximationUsed, ...
        "%s collision decision was not exact waveform evidence.", duplex);
    assert(string(collision.DuplexMode) == duplex && ...
        collision.Collision && collision.OverlapRECount > 0, ...
        "%s did not detect the known same-UE SRS/PUSCH RE collision.", duplex);
    assert(string(collision.Action) == ...
        "defer_srs_preserve_scheduled_pusch", ...
        "%s did not preserve the already scheduled PUSCH.", duplex);
    assert(contains(string(collision.SRSAllocationSource), "nrSRS") && ...
        contains(string(collision.PUSCHAllocationSource), "nrPUSCH"), ...
        "%s collision decision was not backed by Toolbox RE indices.", duplex);

    noOverlapAllocation = double(cfg.phy.pusch.SymbolAllocation);
    srs = sixgr.phy.srs.buildSRSConfigFromScenario(cfg);
    srsStart = double(srs.ToolboxSRS.SymbolStart);
    assert(srsStart >= 1, ...
        "Test scenario must leave at least one symbol before SRS.");
    noOverlapAllocation = [0 srsStart];
    clearGrant = localScheduledPUSCHGrant( ...
        cfg, absoluteSlotOneBased, noOverlapAllocation);
    noCollision = sixgr.phy.frame.resolveSRSPUSCHCollision( ...
        cfg, clearGrant, absoluteSlotOneBased);
    assert(noCollision.Exact && ~noCollision.Collision && ...
        noCollision.OverlapRECount == 0 && ...
        string(noCollision.Action) == "execute_srs", ...
        "%s reported a collision after PUSCH excluded the SRS symbol.", duplex);
end

ok = true;
fprintf("[PASS] testSRSPUSCHExactCollisionFDDTDD shared exact arbitration retained.\n");
end

function absoluteSlotOneBased = localFindLegalActiveSRSSlot(cfg)
strictSRS = sixgr.phy.srs.buildSRSConfigFromScenario(cfg);
[probe, ~] = sixgr.phy.grid.makeCarrier(cfg);
slotsPerFrame = 10 * 2^round(log2(double(probe.SubcarrierSpacing) / 15));
duplex = upper(string(sixgr.phy.frame.resolveDuplexMode(cfg)));

for slot0 = 0:(4 * slotsPerFrame - 1)
    legalUL = true;
    if duplex == "TDD"
        partition = sixgr.util.resolveTDDSlotPartition(cfg, slot0);
        legalUL = logical(partition.AllowUL);
    end
    if ~legalUL
        continue;
    end
    [carrier, ~] = sixgr.phy.grid.makeCarrier(cfg, ...
        "Slot", mod(slot0, slotsPerFrame), ...
        "Frame", floor(slot0 / slotsPerFrame));
    if ~isempty(nrSRSIndices(carrier, strictSRS.ToolboxSRS))
        absoluteSlotOneBased = slot0 + 1;
        return;
    end
end
error("sixgr:test:NoLegalActiveSRSOccasion", ...
    "No legal active SRS occasion was found in four frames.");
end

function grant = localScheduledPUSCHGrant(cfg, slotOneBased, symbols)
pusch = cfg.phy.pusch;
grant = struct( ...
    "UEIndex", 1, ...
    "ScheduledAbsoluteSlot", double(slotOneBased), ...
    "Slot", double(slotOneBased), ...
    "PRBSet", double(pusch.PRBSet), ...
    "SymbolAllocation", double(symbols), ...
    "Modulation", char(string(pusch.modulation)), ...
    "NumLayers", double(pusch.numLayers), ...
    "RNTI", double(pusch.RNTI), ...
    "TransformPrecoding", logical(pusch.transformPrecoding), ...
    "TransmissionScheme", char(string(pusch.TransmissionScheme)), ...
    "NumAntennaPorts", double(pusch.NumAntennaPorts), ...
    "TPMI", double(pusch.TPMI), ...
    "NID", double(pusch.NID), ...
    "MappingType", char(string(pusch.mappingType)));
end
