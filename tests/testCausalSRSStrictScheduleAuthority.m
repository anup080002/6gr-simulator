function ok = testCausalSRSStrictScheduleAuthority()
%TESTCAUSALSRSSTRICTSCHEDULEAUTHORITY Guard YAML-to-nrSRS occasion binding.

setup6GRSimToolkit("Verbose", false);
scenarioPath = fullfile("simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, tempname);

assert(double(cfg.phy.srs.period_slots) == 4 && ...
    double(cfg.phy.srs.period_offset) == 3 && ...
    isequal(double(cfg.phy.srs.slotWithinPeriod1Based(:)).', 4), ...
    "Causal YAML must resolve period 4, zero-based offset 3, one-based occasion 4.");
assert(isscalar(cfg.phy.srs.EnableStartRBHopping) && ...
    ~logical(cfg.phy.srs.EnableStartRBHopping), ...
    ["The SRS frequency_hopping mode must not be coerced into the distinct " + ...
     "Toolbox EnableStartRBHopping boolean."]);

srsCfg = sixgr.phy.srs.buildSRSConfigFromScenario(cfg);
assert(isequal(double(srsCfg.ExpectedSlotSet(:)).', 3) && ...
    string(srsCfg.ExpectedSlotSetSource) == ...
        "phy.srs.slotWithinPeriod1Based+period_offset", ...
    "Strict SRS must validate the same YAML-authored occasion as coupled runtime.");
assert(logical(srsCfg.StrictValidation.StrictValid), ...
    "The resolved causal SRS resource must be strict-valid.");

mapping = sixgr.phy.srs.generateSRSSymbolsAndIndices(srsCfg);
assert(height(mapping.ResourceMappingTable) > 0 && ...
    logical(mapping.Coverage.ConfiguredBandClaimValid) && ...
    double(mapping.Coverage.OccupiedPRBCount) == 24 && ...
    double(mapping.Coverage.CarrierPRBCount) == 25, ...
    "The configured 24-of-25-PRB SRS allocation must produce measured mapping coverage.");

bad = sixgr.util.structSet(cfg, "phy.srs.period_offset", 0);
didThrow = false;
try
    sixgr.phy.srs.buildSRSConfigFromScenario(bad);
catch ME
    didThrow = strcmp(ME.identifier, "sixgr:phy:srs:ScheduleAuthorityMismatch");
end
assert(didThrow, ...
    "A mismatched YAML SRS period offset must fail with typed schedule-authority error.");

badBoolean = scfg.toStruct();
badBoolean.reference_signals.srs.enable_start_rb_hopping = "neither";
didThrow = false;
try
    sixgr.lls6g.buildInternalConfig(badBoolean, tempname);
catch ME
    didThrow = strcmp(ME.identifier, ...
        "sixgr:lls6g:config:InvalidSRSEnableStartRBHopping");
end
assert(didThrow, ...
    "A non-boolean SRS start-RB-hopping authority must fail with a typed error.");

ok = true;
end
