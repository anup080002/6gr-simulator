function ok=test20MHzConnectedTDDConfiguration()
% Config/grid/producer verification, not access or detector qualification.
setup6GRSimToolkit('Verbose',false);
path=fullfile('simulator','configs','scenarios', ...
    'lls_tdd_n40_20mhz_64txru_4rx_cdlc100_impaired.yaml');
s=sixgr.lls6g.config.loadScenarioConfig(path);
cfg=sixgr.lls6g.buildInternalConfig(s,tempname);
assert(s.get('frequency.bandwidth_hz')==20e6 && ...
    string(s.get('frequency.band_name'))=="n40" && ...
    cfg.phy.fc_Hz==2350e6 && cfg.phy.nTxAnt==64 && cfg.phy.nRxAnt==4);
assert(cfg.phy.pdsch.maxRankDefault==4 && cfg.phy.pusch.maxRankDefault==4 && ...
    s.get('canonical_control.mimo.n_layers')==1 && ...
    s.get('link_adaptation.inner_loop_flag') && s.get('link_adaptation.outer_loop_flag'));
assert(cfg.run.totalSlots==60 && cfg.run.totalTime_ms==30 && ...
    ~s.get('run_control.runtime_checkpoint_enable'));
assert(s.get('system.scheduler.maxPRBAllocationPerUE')==51 && ...
    s.get('scheduler.max_prbs_per_grant')==51 && ...
    ~s.get('system.scheduler.fastNREApprox') && string(s.get('system.scheduler.tbsMode'))=="faithful");
assert(s.get('bwp.dl.n_size_bwp')==51 && s.get('bwp.ul.n_size_bwp')==51 && ...
    s.get('pdsch.num_prb')==51 && s.get('pusch.num_prb')==51);
% Exercise the runtime array constructor, not only the YAML element count.
for role=["bs","ue"]
    array=sixgr.rf.AntennaArrayFactory.build(cfg,role);
    assert(isequal(array.ElementFrequencyRangeHz,[2300e6 2400e6]));
end
bad=cfg;
bad.antenna.bs.element.frequencyRangeHz=[3900e6 4100e6];
rejected=false;
try
    sixgr.rf.AntennaArrayFactory.build(bad,"bs");
catch cause
    assert(strcmp(cause.identifier,'AntennaArrayFactory:CarrierOutsideElementFrequencyRange'));
    rejected=true;
end
assert(rejected,'A mismatched inherited antenna operating band must remain invalid.');
carrier=sixgr.phy.grid.makeCarrier(cfg); ofdm=nrOFDMInfo(carrier);
assert(carrier.NSizeGrid==51 && carrier.SubcarrierSpacing==30 && ...
    string(carrier.CyclicPrefix)=="normal" && ofdm.Nfft==1024 && ofdm.SampleRate==30.72e6);
assert(sum(double(ofdm.SymbolLengths))==30720 && numel(ofdm.SymbolLengths)==28 && ...
    abs(51*12*30e3-s.get('global_radio_scope.occupied_bandwidth_hz'))<1e-6);
assert(cfg.phy.ssb.scs_kHz==30 && ...
    s.get('bwp.dl.scs_khz')==30 && s.get('bwp.ul.scs_khz')==30 && ...
    s.get('frame.tdd_common.ReferenceSubcarrierSpacingKHz')==30);
frame=sixgr.phy.FrameStructureEngine(cfg,'FrameCoreOnly',true);
for slot=0:4
    p=frame.SlotPartition(slot);
    if slot<3
        assert(p.AllowDL && ~p.AllowUL && isequal(p.DLSymbolAllocation,[0 14]));
    elseif slot==3
        assert(p.AllowDL && p.AllowUL && isequal(p.DLSymbolAllocation,[0 10]) && ...
            isequal(p.ULSymbolAllocation,[12 2]));
    else
        assert(~p.AllowDL && p.AllowUL && isequal(p.ULSymbolAllocation,[0 14]));
    end
end
common=sixgr.phy.frame.CommonDLResourcePlan(cfg);
common.validateSIB1References();
% The received-MIB/Type-0 path must preserve n40's unpaired Case-C context,
% not fall back to the paired <=3 GHz four-candidate compatibility path.
[type0,~]=sixgr.phy.broadcast.deriveType0PDCCHFromMIB(carrier,cfg, ...
    struct('PDCCHConfigSIB1',cfg.phy.mib.pdcchConfigSIB1),'TimingOnly',true);
assert(type0.SSBTiming.Lmax==8 && ...
    string(type0.SSBTiming.BandAwareResolution.Spectrum)=="unpaired");
assert(cfg.phy.csirs.numResources==8 && cfg.phy.csirs.offset_slots==5 && ...
    isequal(reshape(double(s.get('reference_signals.csi_rs_resource_num_rbs')),1,[]),51*ones(1,8)));
assert(isequal(cfg.phy.csirs.numRBsByResource,51*ones(1,8)));
assert(isequal(double(cfg.phy.ssb.activeCandidateIndices0Based(:).'),0:3) && ...
    cfg.phy.csi.reportPeriodicitySlots==10 && cfg.phy.csi.reportOffsetSlots==8);
assert(cfg.phy.ssb.Lmax==8); % Four active beams in the eight-position Case-C bitmap.
pointA=2350e6-51*12*30e3/2;
ssref=pointA+(12*cfg.phy.ssb.NCRBSSB+cfg.phy.ssb.KSSB)*15e3+120*30e3;
assert(abs(ssref-(1958*1.2e6+5*50e3))<1e-6 && 3*1958+(5-3)/2==5875);
assert(cfg.run.controlGating.trsMaxAgeSlots>=s.get('reference_signals.trs_periodicity_slots'));
ue=struct('UEID',1,'RNTI',1,'ServingCell',1,'PUCCHCell',1, ...
    'ComponentCarrier',cfg.phy.frame.DefaultIdentity.ScheduledCCID, ...
    'ActiveULBWP',cfg.phy.frame.DefaultIdentity.ULBWPID);
calendar=sixgr.truth.configuredCSIReportCalendar(cfg,ue,59);
assert(height(calendar)==1 && calendar.ULResourceAvailable);
prach=sixgr.rach.PRACHConfig(cfg,'NumPRACHOccasions',1,'NumTrials',1);
assert(prach.NSizeGrid==51 && prach.CarrierSCSkHz==30 && prach.PRACHSubcarrierSpacing==30 && ...
    prach.NumTxAntennas==4 && prach.NumRxAntennas==64 && ...
    prach.PRACHConfigurationIndex==157 && prach.FirstActiveOccasion.SlotIndex1==10);
ra=sixgr.mac.ra.RAConfig(cfg,'UEId',1,'AttemptId',1);
assert(ra.Msg2PDSCH.PRBStart==15 && ra.Msg4PDSCH.PRBStart==15 && ...
    ra.Msg4DCIReference.FrequencyReferenceStart==15);
probe=struct('Direction',"UL",'ControlAbsoluteSlot',0, ...
    'ControlSymbolAllocation',double(cfg.phy.pdcch.symbolAllocation), ...
    'SymbolAllocation',double(cfg.phy.pusch.symbolAllocation),'HARQProcess',0);
timing=sixgr.phy.frame.TimingRelationEngine.resolveProductionGrant(cfg,probe);
assert(timing.Valid && timing.K2==4 && timing.DataAbsoluteSlot==4);
current=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,5);
[tx,info]=sixgr.phy.ul.SRS_Tx(current);
assert(tx.Carrier.NSizeGrid==51 && tx.SRS.CSRS==12 && tx.SRS.BSRS==0 && ...
    tx.SRS.NumSRSPorts==4 && tx.SRSOccupiedPRBCount==48 && ...
    tx.SRSFrequencyPRBStart==0 && tx.SRSFrequencyPRBEnd==47 && ...
    info.OFDMInfo.SampleRate==30.72e6 && size(tx.Waveform,2)==4 && ...
    abs(tx.SRSBandwidthFraction-48/51)<1e-12);
assert(cfg.channel.pathlossEnabled && ...
    ~sixgr.rf.isFixedSNRLinkAuthority(cfg) && ...
    sixgr.rf.fixedSNRPowerReferenceMode(cfg)=="absolute_calibrated_sqrt_mw" && ...
    string(cfg.run.noiseOperatingMode)=="receiver_noise_figure_thermal_noise" && ...
    string(s.get('channels.profile'))=="CDL-C" && s.get('channels.delay_spread_ns')==100);
for field=["cfo_enabled","phase_noise_enabled","iq_imbalance_enabled", ...
        "pa_nonlinearity_enabled","adc_quantization_enabled","dac_quantization_enabled", ...
        "timing_offset_enabled"]
    assert(s.get("impairments."+field));
end
for field=["save_csv","save_mat","save_figures","save_png","save_yaml_snapshot","save_json_snapshot"]
    assert(s.get("output."+field));
end
assert(~s.get('output.emit_placeholder_artifacts'));
% The server parent must remain 100 MHz; this is a child, not its replacement.
parent=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_adaptation.yaml');
assert(parent.get('frequency.n_size_grid')==273 && parent.get('frequency.bandwidth_hz')==100e6);
ok=true;
disp('20MHZ_CONNECTED_TDD_CONFIG_PASS: 51 PRB, uniform 30 kHz, 64x4, rank ceiling 4; scenario acceptance NOT tested');
end
