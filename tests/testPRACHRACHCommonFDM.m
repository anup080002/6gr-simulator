function ok = testPRACHRACHCommonFDM()
% Native RACH-common adapter/Msg1 TX regression, not a received-SIB1 or RA test.
% Common parameters are declared test inputs. Occasion coordinates come from
% the production native resolver; the reference grid/waveform is constructed
% directly with the original nrCarrierConfig/nrPRACHConfig tuple. No channel,
% RF, detector, received control, random preamble selection or RA acceptance.
setup6GRSimToolkit('Verbose',false,'RunToolboxChecks',false);
parent=fullfile(pwd,'results','validation','prach_rach_common_fdm');
if ~isfolder(parent), mkdir(parent); end
output=tempname(parent); mkdir(output);
fprintf('PRACH_RACH_COMMON_FDM_EVIDENCE %s\n',output);
count=0;
for fdm=[1 2 4 8]
    cfg=struct('frequency',struct('center_frequency_hz',3.5e9), ...
        'channel',struct('model',"AWGN",'awgnOnly',true), ...
        'phy',struct('duplex',struct('mode',"TDD"), ...
        'carrier',struct('SubcarrierSpacing',30,'NSizeGrid',100, ...
        'NStartGrid',0,'NCellID',17,'CyclicPrefix',"normal")), ...
        'random_access',struct('frequency_range',"FR1", ...
        'msg1_fdm',1,'num_tx_antennas',1));
    % Deliberately disagree with the installed RACH-common operand for FDM
    % 2/4/8: mutable scenario policy must not replace its received owner.
    original=sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
        'FrequencyRange',"FR1",'DuplexMode',"TDD", ...
        'ConfigurationIndex',167,'CarrierSubcarrierSpacingKHz',30, ...
        'CarrierCyclicPrefix',"normal",'NSizeGrid',100,'NStartGrid',0, ...
        'NCellID',17,'PRACHSubcarrierSpacingKHz',30,'SequenceIndex',0, ...
        'PreambleIndex',11,'RestrictedSet',"UnrestrictedSet", ...
        'ZeroCorrelationZone',0,'Msg1FDM',fdm,'Msg1FrequencyStart',0);
    assert(original.ResolvedValid && ~original.FallbackUsed && ...
        isequal(unique(original.Occasions.FrequencyIndex),(0:fdm-1).'));
    % Nonzero frequency first: the pre-repair adapter must fail the real
    % materialization, not pass because an FDM=1 default happens to fit f=0.
    for frequency=unique([fdm-1 0],'stable')
        row=original.Occasions(find(original.Occasions.FrequencyIndex==frequency,1),:);
        for repetition=0:1
            count=count+1;
            ra=localCommon(original,row,repetition,fdm);
            built=sixgr.phy.ra.buildPRACHConfigFromRACHCommon(cfg,ra);
            stem=fullfile(output,sprintf('fdm%d_frequency%d_period%d',fdm,frequency,repetition));
            % Save original operands even if the production waveform guard
            % rejects the currently dropped-FDM adapter. That rejection is
            % a failing regression, never an accepted negative outcome.
            save([stem '.mat'],'cfg','original','row','ra','built');
            try
                [actual,occasion]=sixgr.phy.ra.generateMsg1PRACHWaveform(cfg,ra);
            catch cause
                failure=struct('Identifier',string(cause.identifier),'Message',string(cause.message));
                save([stem '.mat'],'failure','-append');
                rethrow(cause);
            end
            [carrier,prach,indices,symbols,grid,waveform,ofdm]=localNative(original,row,ra,repetition);
            receipt=struct('OriginalFDM',fdm,'AdapterFDM',built.Msg1FDM, ...
                'OriginalFrequencyIndex',frequency,'ActualFrequencyIndex',occasion.FrequencyIndex, ...
                'OriginalOrdinal',ra.PRACHOccasionOrdinal,'ActualOrdinal',occasion.Ordinal, ...
                'OriginalPRACHSlot',prach.NPRACHSlot,'ActualPRACHSlot',actual.PRACH.NPRACHSlot, ...
                'ActualWaveformSHA256',sixgr.phy.waveform.WaveformHash.numeric(actual.Waveform), ...
                'NativeWaveformSHA256',sixgr.phy.waveform.WaveformHash.numeric(waveform));
            save([stem '.mat'],'receipt','occasion','-append');
            assert(built.Msg1FDM==fdm && actual.PRACHRuntimeConfig.Msg1FDM==fdm, ...
                'test:PRACHRACHCommonFDMLost','The original RACH-common Msg1FDM was not installed.');
            assert(occasion.Ordinal==ra.PRACHOccasionOrdinal && ...
                occasion.SlotIndex0==ra.PRACHAbsoluteSlot && ...
                occasion.Carrier.NFrame==ra.PRACHOccasionFrame && ...
                occasion.Carrier.NSlot==ra.PRACHOccasionSlot && ...
                occasion.PRACHSlotIndex0==prach.NPRACHSlot && ...
                occasion.ActivePRACHSlot==row.ActivePRACHSlot && ...
                occasion.TimeIndex==row.TimeIndex && ...
                occasion.FrequencyIndex==row.FrequencyIndex && ...
                occasion.RARNTISymbolIndex==row.RARNTISymbolIndex && ...
                occasion.RARNTISlotIndex==row.RARNTISlotIndex, ...
                'The complete original RO tuple must survive Msg1 preparation.');
            assert(actual.PRACH.NPRACHSlot==prach.NPRACHSlot && ...
                actual.PRACH.ActivePRACHSlot==prach.ActivePRACHSlot && ...
                actual.PRACH.TimeIndex==prach.TimeIndex && ...
                actual.PRACH.FrequencyIndex==prach.FrequencyIndex && ...
                actual.PRACH.PreambleIndex==ra.PreambleIndex && ...
                actual.PRACH.FrequencyStart==ra.FrequencyStart && ...
                actual.RARNTI==ra.RARNTI && ...
                sixgr.phy.ra.computeRARNTIFromOccasion(occasion)==ra.RARNTI);
            assert(isequal(actual.Indices,indices) && isequal(actual.Symbols,symbols) && ...
                isequal(actual.Grid,grid) && isequal(actual.WaveformPortResourceGrid,grid) && ...
                isequal(actual.Waveform,waveform) && actual.SampleRate_Hz==ofdm.SampleRate && ...
                actual.OFDMInfo.Windowing==0 && ~isempty(waveform) && all(isfinite(waveform),'all'), ...
                'Msg1 must use the exact original native frequency/time grid and waveform.');
            assert(carrier.NCellID==actual.Carrier.NCellID && ...
                actual.PRACHOccasionOrdinal==occasion.Ordinal);
            % Existing guards stay active; do not repair this defect by
            % suppressing time/RA-RNTI comparisons or rewriting the evidence.
            if repetition==0
                for invalid={[],NaN,0,3,16,[1 2],"two"}
                    bad=ra; bad.Msg1FDM=invalid{1};
                    localReject(@()sixgr.phy.ra.buildPRACHConfigFromRACHCommon(cfg,bad), ...
                        'sixgr:phy:ra:InvalidRACHCommonMsg1FDM');
                end
                bad=rmfield(ra,'Msg1FDM');
                localReject(@()sixgr.phy.ra.buildPRACHConfigFromRACHCommon(cfg,bad), ...
                    'sixgr:phy:ra:InvalidRACHCommonMsg1FDM');
                bad=ra; bad.PRACHAbsoluteSlot=bad.PRACHAbsoluteSlot+1;
                localReject(@()sixgr.phy.ra.generateMsg1PRACHWaveform(cfg,bad), ...
                    'sixgr:phy:ra:PRACHOccasionTimeMismatch');
                bad=ra; bad.RARNTI=bad.RARNTI+1;
                localReject(@()sixgr.phy.ra.generateMsg1PRACHWaveform(cfg,bad), ...
                    'sixgr:phy:ra:PRACHOccasionRARNTIMismatch');
            end
            fprintf('PRACH_RACH_COMMON_FDM fdm=%d frequency=%d period=%d slot0=%d ordinal=%d\n', ...
                fdm,frequency,repetition,occasion.SlotIndex0,occasion.Ordinal);
        end
    end
end
ok=true;
fprintf('PASS testPRACHRACHCommonFDM: %d native TX comparisons; RF=0 receiver=0.\n',count);
end

function ra=localCommon(original,row,repetition,fdm)
slot=row.AbsoluteSlot+repetition*original.PeriodCarrierSlots;
ra=struct('ScenarioName',"declared_rach_common_fdm_adapter", ...
    'CarrierSCSkHz',30,'NSizeGrid',100,'NCellID',17, ...
    'PRACHConfigurationIndex',167,'PRACHFormat',original.Format, ...
    'PRACHSubcarrierSpacing',30,'RootSequenceIndex',0,'PreambleIndex',11, ...
    'ZeroCorrelationZoneConfig',0,'RestrictedSetType',"UnrestrictedSet", ...
    'FrequencyStart',0,'Msg1FDM',fdm,'PRACHAbsoluteSlot',slot, ...
    'PRACHOccasionFrame',floor(slot/20),'PRACHOccasionSlot',mod(slot,20), ...
    'PRACHOccasionSymbol',row.StartSymbol,'PRACHFrequencyIndex',row.FrequencyIndex, ...
    'PRACHOccasionOrdinal',row.Ordinal+repetition*height(original.Occasions), ...
    'PRACHOccasionResolution',original, ...
    'RARNTI',sixgr.phy.ra.computeRARNTI('SymbolIndex',row.RARNTISymbolIndex, ...
        'SlotIndex',row.RARNTISlotIndex,'FrequencyIndex',row.FrequencyIndex));
end

function [carrier,prach,indices,symbols,grid,waveform,ofdm]=localNative(original,row,ra,repetition)
carrier=nrCarrierConfig('SubcarrierSpacing',30,'NSizeGrid',100, ...
    'NStartGrid',0,'NCellID',17,'NFrame',ra.PRACHOccasionFrame, ...
    'NSlot',ra.PRACHOccasionSlot,'CyclicPrefix','normal');
prach=nrPRACHConfig('FrequencyRange','FR1','DuplexMode','TDD', ...
    'ConfigurationIndex',167,'SubcarrierSpacing',30,'SequenceIndex',0, ...
    'PreambleIndex',11,'RestrictedSet','UnrestrictedSet','ZeroCorrelationZone',0, ...
    'FrequencyStart',0,'ActivePRACHSlot',row.ActivePRACHSlot, ...
    'NPRACHSlot',row.PRACHSlot+repetition*original.PeriodPRACHSlots, ...
    'TimeIndex',row.TimeIndex,'FrequencyIndex',row.FrequencyIndex);
indices=nrPRACHIndices(carrier,prach);
symbols=nrPRACH(carrier,prach);
grid=nrPRACHGrid(carrier,prach); grid(indices)=symbols;
[waveform,ofdm]=nrPRACHOFDMModulate(carrier,prach,grid,'Windowing',0);
end

function localReject(action,identifier)
try, action(); catch cause
    assert(strcmp(cause.identifier,identifier),'Expected %s, got %s.',identifier,cause.identifier);
    return;
end
error('test:MissingPRACHRACHCommonGuard','Expected %s.',identifier);
end
