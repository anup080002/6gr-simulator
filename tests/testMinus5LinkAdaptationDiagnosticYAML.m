function ok = testMinus5LinkAdaptationDiagnosticYAML()
%TESTMINUS5LINKADAPTATIONDIAGNOSTICYAML Guard the causal -5 dB DL/UL profiles.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

profiles = [ ...
    "configs/lls/pdsch_awgn_link_adaptation_minus5_diagnostic.yaml", ...
    "configs/lls/pusch_awgn_link_adaptation_minus5_diagnostic.yaml"];
expectedLinks = ["PDSCH", "PUSCH"];
for i = 1:numel(profiles)
    [cfg, ~] = sixgr.lls.loadConfig(profiles(i));
    assert(upper(string(cfg.simulation.link)) == expectedLinks(i), ...
        "Diagnostic profile %s resolved the wrong link direction.", profiles(i));
    assert(isequal(double(cfg.simulation.snrDb(:).'), -5) && ...
        double(cfg.simulation.minTransportBlocks) == 10 && ...
        double(cfg.simulation.maxTransportBlocks) == 10, ...
        "Diagnostic profile %s must remain a fixed 10-TB -5 dB run.", profiles(i));
    assert(logical(cfg.linkAdaptation.enabled) && ...
        string(cfg.linkAdaptation.mcsTable) == "qam64_table1" && ...
        string(cfg.linkAdaptation.cqiTable) == "table1" && ...
        double(cfg.linkAdaptation.initialMCSIndex) == 4 && ...
        double(cfg.linkAdaptation.minimumMCSIndex) == 0 && ...
        double(cfg.linkAdaptation.maximumMCSIndex) == 28 && ...
        double(cfg.linkAdaptation.feedbackDelaySlots) == 1 && ...
        double(cfg.linkAdaptation.thresholdComparisonToleranceDb) == 1e-9 && ...
        string(cfg.linkAdaptation.outOfRangeCQIPolicy) == ...
            "minimum_mcs_waveform_probe", ...
        "Diagnostic profile %s lost its table-1 causal ILLA authority.", profiles(i));
    assert(logical(cfg.linkAdaptation.olla.enabled) && ...
        double(cfg.linkAdaptation.olla.targetBLER) == 0.1 && ...
        double(cfg.linkAdaptation.olla.initialOffsetDb) == 0 && ...
        double(cfg.linkAdaptation.olla.ackStepDb) == 0.1 && ...
        double(cfg.linkAdaptation.olla.nackStepDb) == 0.9 && ...
        double(cfg.linkAdaptation.olla.minimumOffsetDb) == -6 && ...
        double(cfg.linkAdaptation.olla.maximumOffsetDb) == 6, ...
        "Diagnostic profile %s lost its YAML-owned OLLA policy.", profiles(i));
end

ok = true;
end
