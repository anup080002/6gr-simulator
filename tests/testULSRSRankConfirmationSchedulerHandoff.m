function ok=testULSRSRankConfirmationSchedulerHandoff()
% Authored receiver-delivery boundary cases, not SRS waveform qualification.
% Exercise the installed H4 policy without changing its two-report rule.
setup6GRSimToolkit('Verbose',false);
source=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_gate.yaml');
cfg=sixgr.lls6g.buildInternalConfig(source,tempname);
cfg.phy.linkAdaptation.initialSpatialConfirmationReports=2; % Explicit two-report initial fixture.
assert(cfg.phy.pusch.numLayers==1 && cfg.phy.pusch.maxLayers==4 && ...
    cfg.phy.linkAdaptation.rankIncreaseConfirmationReports==2);
reported=[2 2 2 1 4 4 4]; accepted=[1 2 2 1 1 4 4];
held=[true false false false true false false];
state=emptyState(cfg);
for k=1:numel(reported)
    report=struct('CQI',10,'RI',reported(k),'PMI',0,'CRI',NaN, ...
        'SINR_dB',NaN,'SourceSlot',5*k-1,'DueSlot',5*k, ...
        'DeliveredSlot',5*k,'ServingCell',1);
    [state,report]=sixgr.truth.CoupledTruthRuntime.applyDeliveredCSIAdaptationRuntime( ...
        state,report,1,'UL',struct());
    assert(report.RI==reported(k),'Keep measured RI separate from accepted rank.');
    assert(report.SchedulerSpatialDecisionDeferred==held(k) && ...
        report.SchedulerAcceptedRank==accepted(k), ...
        'sixgr:test:ULRankConfirmationBypassed', ...
        'UL report %d must retain the configured rank-confirmation decision.',k);
    assert(state.ULLinkAdaptationState{1}.SchedulerAcceptedRank==accepted(k));
    if held(k)
        assert(report.RankUpdateStatus=="pending_increase_confirmation" && ...
            isnan(report.MCSIndex),'Candidate-rank quality cannot schedule an unconfirmed rank.');
    end
end

% The SRS producer's consumer must honor the same decision, not copy raw RI
% over the held scheduler state after invoking the adaptation calculation.
state=emptyState(cfg);
for k=1:numel(reported)
    slot=5*k;
    row=declaredSRS(reported(k),slot);
    unchanged=row;
    previous=state.LatestULFeedback;
    state=sixgr.truth.CoupledTruthRuntime.updateLatestULFeedbackFromSRSTrialRuntime( ...
        state,1,row,slot);
    assert(isequaln(row,unchanged),'Do not rewrite the received observation.');
    if held(k)
        assert(isequaln(state.LatestULFeedback,previous), ...
            'sixgr:test:PendingSRSOverwroteScheduler', ...
            'Unconfirmed SRS cannot refresh old quality/age or install a candidate RI/TPMI.');
    else
        latest=state.LatestULFeedback;
        assert(latest.Valid && latest.RI==reported(k) && latest.PMI==0 && ...
            latest.SourceSlot==slot && latest.DeliveredSlot==slot && ...
            isfinite(latest.MCSIndex),'Admit complete confirmed SRS quality/spatial decisions.');
    end
    assert(state.ULLinkAdaptationState{1}.SchedulerAcceptedRank==accepted(k) && ...
        state.ULLinkAdaptationState{1}.OLLAUpdateCount==0, ...
        'SRS changes ILLA, not the HARQ-owned OLLA state.');
    if k==1 || k==2
        previous=state;
        state=sixgr.truth.CoupledTruthRuntime.updateLatestULFeedbackFromSRSTrialRuntime( ...
            state,1,row,slot);
        assert(isequaln(state,previous),'sixgr:test:DuplicateSRSChangedAdaptation', ...
            'Duplicate SRS must not confirm rank or refresh scheduler feedback.');
    end
    if k==2
        previous=state;
        state=sixgr.truth.CoupledTruthRuntime.updateLatestULFeedbackFromSRSTrialRuntime( ...
            state,1,declaredSRS(1,5),5);
        assert(isequaln(state,previous),'sixgr:test:StaleSRSChangedAdaptation', ...
            'Older SRS must not roll back the confirmed rank or quality.');
    end
end
assert(state.CfgMobility.phy.pusch.numLayers==1, ...
    'Per-UE accepted rank must not mutate installed initial rank.');
fprintf('UL_SRS_RANK_CONFIRMATION_HANDOFF_PASS reports=7 accepted_ranks=1,2,2,1,1,4,4 waveform_qualification=0\n');
ok=true;
end

function state=emptyState(cfg)
latest=sixgr.truth.CoupledTruthRuntime.emptyLatestFeedbackRowRuntime();
state=struct('CfgMobility',cfg,'NumUsers',1,'DLSchedulers',{{}}, ...
    'ULSchedulers',{{}},'DLLinkAdaptationState',{{struct()}}, ...
    'ULLinkAdaptationState',{{struct()}},'SlotDuration_s',sixgr.time.slotDurationSec(cfg), ...
    'LatestDLFeedback',latest,'LatestULFeedback',latest,'PendingCSITable',table());
end

function row=declaredSRS(rank,slot)
% Values intentionally supplied at the delivery API for an ownership test.
% They are never exported as physical received measurements or BLER data.
row=struct('Slot',slot,'ServingCell',1,'SINR_dB',20,'WidebandCQI',10, ...
    'RIEstimate',rank,'TPMIEstimate',0,'SRSBandwidthCoverageStatus',"full_band", ...
    'SRSBandwidthFraction',272/273,'PredictedPUSCHMinimumLayerSINR_dB',20, ...
    'PredictedPUSCHPostEqSINRSource', ...
        "receiver_measured_srs_reference_power_selected_ri_tpmi_mmse_layer_prediction", ...
    'PredictedPUSCHPostEqSINRValueRole', ...
        "power_plane_calibrated_predicted_pusch_data_channel_scheduling_input", ...
    'PredictedPUSCHPostEqSINRValueStatus',"PASS", ...
    'PredictedPUSCHPostEqSINRAnchor_dB',20, ...
    'PredictedPUSCHPostEqSINRAnchorSource',"measured_ul_srs_pilot_reconstruction_sinr", ...
    'PredictedPUSCHPostEqSINRPowerReferencePlane',"receiver_srs_resource_elements_after_ofdm_demodulation", ...
    'PredictedPUSCHReferenceSignalPower',1,'PredictedPUSCHDisturbancePower',.01, ...
    'PUSCHToSRSReferenceEnergyRatio',1,'PUSCHToSRSReferenceEnergySource', ...
        "normalized_fixed_snr_unit_grid_reference_no_device_power_scaling");
end
