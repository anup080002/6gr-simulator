function ok = testCanonicalWideCSVReadback()
%TESTCANONICALWIDECSVREADBACK Wide runtime rows survive persisted reduction.

setup6GRSimToolkit("Verbose", false);
root = tempname;
mkdir(fullfile(root, "air_interface", "csv"));
cleanup = onCleanup(@()localRemove(root)); %#ok<NASGU>

T = table("DL", 0, 1, 1, 2, 1, true, 1064, 1064, 1.064, 0, 1064, 1e-3, ...
    "1;2;3;4", "a;b;c", ...
    'VariableNames', {'Direction','SNR_dB','Frame','Slot','UEID','MCS', ...
    'CRCPass','TBSize_bits','GoodBits','Goodput_Mbps','BitErrors','BitsCompared', ...
    'SlotDuration_s','WideArrayText','LineageText'});
for index = 1:1000
    T.(sprintf('RuntimeField%04d', index)) = string(index) + ";" + string(index + 1);
end
sixgr.util.csvWriteTable(fullfile(root, "air_interface", "csv", ...
    "dl_pdsch_trials.csv"), T);

U = T;
U.Direction(:) = "UL";
sixgr.util.csvWriteTable(fullfile(root, "air_interface", "csv", ...
    "ul_pusch_trials.csv"), U);

roundTrip = sixgr.util.csvReadTable(fullfile(root, "air_interface", ...
    "csv", "dl_pdsch_trials.csv"));
assert(height(roundTrip) == 1 && width(roundTrip) == width(T));
assert(ismember("Direction", string(roundTrip.Properties.VariableNames)) && ...
    string(roundTrip.Direction(1)) == "DL");

raw = sixgr.kpi.loadDirectionRawTables(struct(), ...
    "RunFolder", root, "PreferPersistedPrimary", true);
assert(height(raw.DL) == 1 && height(raw.UL) == 1 && ...
    width(raw.DL) == width(T) && width(raw.UL) == width(T));
reconstructed = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw, ...
    "RunId", "wide_csv", "ScenarioName", "wide_csv", ...
    "SourcePaths", raw.Paths, "MeasurementWindowSec", 1e-3, ...
    "EffectiveBandwidthHz", 5e6);
dlAudit = reconstructed.SchemaAudit( ...
    reconstructed.SchemaAudit.Direction == "DL", :);
assert(~isempty(dlAudit) && all(dlAudit.Present) && all(dlAudit.TypeValid), ...
    "Canonical wide DL rows lost required KPI fields after CSV readback.");
assert(height(reconstructed.RowContributionsDL) == 1 && ...
    height(reconstructed.HARQDeliveryTraceDL) == 1, ...
    "DL KPI reconstruction must retain the persisted primary trial.");

ok = true;
end

function localRemove(pathValue)
if isfolder(pathValue)
    rmdir(pathValue, "s");
end
end
