function ok = testPersistedRuntimeEvidenceRefinalization()
%TESTPERSISTEDRUNTIMEEVIDENCEREFINALIZATION Exact fixed rows feed recovery.

setup6GRSimToolkit("Verbose", false);
root = tempname;
mkdir(root);
cleanup = onCleanup(@() localRemove(root)); %#ok<NASGU>

scenarioPath = fullfile(fileparts(fileparts(mfilename("fullpath"))), ...
    "simulator", "configs", "scenarios", "master_sinr_sweep.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, root);
% Emulate a legacy persisted internal config that omitted the campaign
% classification.  The immutable primary runtime rows below remain the
% final authority and must be propagated to every downstream reducer.
cfg.run.fixedLinkCampaignOnly = false;
cfg.run.fixed_link_campaign_only = false;
cfg.run.runTag = "persisted_refinalization_fixture";
% The fixture exercises an interference-disabled AWGN link. Make the
% configured authority explicit so the reconciliation compares like with
% like instead of inheriting unrelated master-catalog study defaults.
cfg.interference.inter_cell_execution_mode = "none";
cfg.interference.intra_cell_execution_mode = "none";
cfg.interference.interCellEnabled = false;
cfg.interference.intraCellEnabled = false;

layout = sixgr.report.resultLayout(root);
sixgr.util.ensureFolder(layout.AirInterfaceCSVDir);
sixgr.analytics.writeAnalysisTable(fullfile(layout.AirInterfaceCSVDir, ...
    "dl_fixed_link_campaign_trials.csv"), localFixedTrials("DL"));
sixgr.analytics.writeAnalysisTable(fullfile(layout.AirInterfaceCSVDir, ...
    "ul_fixed_link_campaign_trials.csv"), localFixedTrials("UL"));
linkKPIs = table(["DL_PDSCH_Throughput";"UL_PUSCH_Throughput"], ...
    [true;true], [false;false], ...
    'VariableNames', {'Case','Ok','Skipped'});
sixgr.util.csvWriteTable(fullfile(layout.AirInterfaceCSVDir, ...
    "link_kpis.csv"), linkKPIs);

loaded = sixgr.analytics.loadAllTrialData(root);
assert(height(loaded.dl) == 2 && height(loaded.ul) == 2, ...
    "The canonical loader must recover fixed-link primary trial filenames.");

result = sixgr.truth.refinalizePersistedLLSRuntimeEvidence( ...
    cfg, root, "RunTag", cfg.run.runTag);
assert(result.RawEvidencePresent && result.DLTrialRows == 2 && result.ULTrialRows == 2, ...
    "Refinalization must report the exact persisted DL/UL row counts.");
assert(result.FixedLinkCampaignOnly, ...
    ["Refinalization must recognize persisted FixedLinkCampaign runtime " ...
    "rows even when a legacy internal config omitted that authority."]);
assert(result.DerivedTablesGenerated && result.EnergyEvidenceGenerated && ...
    result.MeasuredSINREvidenceGenerated && ...
    result.Phase7RefreshCompleted && ...
    string(result.Phase7RefreshStatus) == ...
    "refreshed_from_finalized_persisted_runtime_evidence" && ...
    result.SourceCSVFinalizationCompleted && ...
    result.LinkKPIReconstructionCompleted, ...
    "Persisted primary rows must feed derived, energy and measured-SINR exporters.");
phase7 = readtable(fullfile(layout.ReportCSVDir, "phase7_truth_gates.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
mobilityKPI = readtable(fullfile(layout.ReportCSVDir, ...
    "mobility_kpi_reconciliation.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
assert(height(phase7) == 1 && height(mobilityKPI) == 1 && ...
    localLogical(phase7.MobilityKpiReconciliationOk(1)) == ...
    localLogical(mobilityKPI.MobilityKpiReconciliationOk(1)), ...
    ["Persisted-runtime finalization must refresh Phase 7 after its " ...
    "reconciliation producers so the two artifacts cannot disagree."]);
assert(~result.BrowserContractRefreshAttempted && ...
    ~result.BrowserContractRefreshOk && ...
    string(result.BrowserContractRefreshStatus) == ...
    "auto_skipped_no_existing_browser_contract", ...
    ["A nonterminal persisted-runtime fixture with no prior browser " ...
    "contract must not launch or claim browser publication."]);
assert(~result.Ok && ~result.FixedSweepEvidenceGenerated && ...
    string(result.FixedSweepStatus) == "persisted_fixed_sweep_summary_missing", ...
    "A missing fixed-sweep summary must remain an explicit fail-closed condition.");

for pathValue = [ ...
        fullfile(layout.ReportCSVDir, "noise_reconciliation.csv")
        fullfile(layout.ReportCSVDir, "interference_accounting.csv")
        fullfile(layout.ReportCSVDir, "canonical_kpi_ledger.csv")
        fullfile(layout.RFCSVDir, "energy_timeline_trace.csv")
        fullfile(layout.ReportDir, "json", "runtime_evidence_refinalization.json")].'
    assert(exist(pathValue, "file") == 2, ...
        "Refinalization did not publish %s.", pathValue);
end

noise = readtable(fullfile(layout.ReportCSVDir, "noise_reconciliation.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
interference = readtable(fullfile(layout.ReportCSVDir, "interference_accounting.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
ledger = readtable(fullfile(layout.ReportCSVDir, "canonical_kpi_ledger.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
if ~(all(localLogical(interference.InterferenceAccountingOk)) && ...
        all(localLogical(interference.ObservedDisabledIdentity)))
    disp(interference);
end
assert(all(localLogical(noise.NoiseReconciliationOk)), ...
    "Recovered noise reconciliation must be backed by runtime variance lineage.");
assert(all(localLogical(interference.InterferenceAccountingOk)) && ...
    all(localLogical(interference.ObservedDisabledIdentity)), ...
    "Recovered interference-off evidence must be an observed disabled identity.");
reloadedTrials = sixgr.analytics.loadAllTrialData(root);
expectedDLSource = "not_emitted_by_active_dl_fixed_link_campaign_trials_runtime";
expectedULSource = "not_emitted_by_active_ul_fixed_link_campaign_trials_runtime";
assert(all(string(reloadedTrials.dl.InterferencePowerSource) == expectedDLSource) && ...
    all(string(reloadedTrials.ul.InterferencePowerSource) == expectedULSource), ...
    ["Persisted source canonicalization must repair the known stale active " ...
    "interference token before derived reconciliation runs."]);
assert(localLogical(ledger.CanonicalKpiLedgerOk(1)) && ...
    ~localLogical(ledger.AccessKpiApplicable(1)) && ...
    ~localLogical(ledger.SchedulerKpiApplicable(1)), ...
    "Fixed-link KPI applicability must remain explicit during recovery.");

kpi = readtable(fullfile(layout.AirInterfaceCSVDir, "lls_kpi_summary.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
assert(all(ismember(["Direction","TrialCount","SourceArtifact"], ...
    string(kpi.Properties.VariableNames))) && height(kpi) == 4, ...
    "Directional measured-SINR KPI rows must remain the final summary authority.");
assert(all(endsWith(string(kpi.SourceArtifact), ...
    "_fixed_link_campaign_trials.csv")), ...
    "Derived KPI rows must name the exact fixed-link primary source files.");

% Terminal finalization performs the same sanitizer once more.  That pass
% must not invalidate source widths or hashes already sealed into the KPI
% manifest.
sixgr.truth.sanitizeLLSArtifactCSVs(root);
kpiManifest = readtable(fullfile(layout.ReportCSVDir, ...
    "kpi_source_table_manifest.csv"), "VariableNamingRule", "preserve", ...
    "TextType", "string");
manifestRows = find(localLogical(kpiManifest.Exists));
assert(~isempty(manifestRows), ...
    "KPI source manifest must contain persisted source rows.");
for manifestIndex = manifestRows(:).'
    sourcePath = fullfile(root, strrep(char(kpiManifest.SourceTablePath(manifestIndex)), ...
        "/", filesep));
    assert(exist(sourcePath, "file") == 2, ...
        "KPI manifest source disappeared after final sanitization: %s", sourcePath);
    sourceTable = readtable(sourcePath, "FileType", "text", "Delimiter", ",", ...
        "ReadVariableNames", true, "VariableNamingRule", "preserve");
    assert(double(kpiManifest.RowCount(manifestIndex)) == height(sourceTable) && ...
        double(kpiManifest.ColumnCount(manifestIndex)) == width(sourceTable), ...
        "KPI manifest dimensions are stale after final sanitization: %s", sourcePath);
    observedSourceHash = sixgr.kpi.hashKPISourceRows(sourceTable);
    assert(string(kpiManifest.FileHash(manifestIndex)) == observedSourceHash, ...
        sprintf(['KPI manifest semantic-row hash is stale after final sanitization: %s ' ...
        'manifest=%s observed=%s'], sourcePath, ...
        char(string(kpiManifest.FileHash(manifestIndex))), ...
        char(observedSourceHash)));
end

fer = result.DerivedArtifacts.ErrorRateSummary;
assert(ismember("ObservedFrames", string(fer.Properties.VariableNames)), ...
    "Derived FER table is missing ObservedFrames runtime evidence.");
assert(all(double(fer.ObservedFrames) == 2), ...
    "FER must not alias frame numbers that restart at each fixed-link SNR point.");

try
    sixgr.truth.refinalizePersistedLLSRuntimeEvidence( ...
        cfg, root, "RunTag", "different_recovery_label");
    error("sixgr:test:ExpectedRunIdentityMismatch", ...
        "A caller-supplied run-identity mismatch was incorrectly accepted.");
catch ME
    assert(string(ME.identifier) == ...
        "sixgr:truth:refinalize:PersistedRunIdentityMismatch", ...
        "Unexpected run-identity mismatch error: %s", ME.identifier);
end

ok = true;
fprintf("PASS testPersistedRuntimeEvidenceRefinalization: persisted truth rows refinalized.\n");
end

