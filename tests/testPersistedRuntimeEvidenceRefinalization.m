function tf = localLogical(values)
if islogical(values)
    tf = logical(values(:));
elseif isnumeric(values)
    tf = isfinite(double(values(:))) & double(values(:)) ~= 0;
else
    token = lower(strtrim(string(values(:))));
    tf = token == "1" | token == "true" | token == "yes" | token == "pass" | token == "ok";
end
end

