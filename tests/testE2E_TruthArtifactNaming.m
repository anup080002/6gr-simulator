function ok = testE2E_TruthArtifactNaming()
%TESTE2E_TRUTHARTIFACTNAMING Verify truth-mode E2E artifacts are explicit.

setup6GRSimToolkit("Verbose", false);
cfg = sixgr.config.defaultConfig();
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.run.seed = 17;

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmp, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", 0.02, ...
    "E2EMaxSlots", 24, ...
    "E2EUECount", 2, ...
    "E2ETrafficModel", "xr", ...
    "E2EAirModel", "truth", ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", false, ...
    "GenerateCampaignPlots", false, ...
    "E2EStrictValidation", false, ...
    "E2ETruthMaxSlots", 28);

S = rep.E2E.SummaryTable(1,:);
assert(string(S.ExecutionMode) == "TRUTH_REPLAY", "Truth run must expose TRUTH_REPLAY execution mode.");
assert(string(S.ArtifactMode) == "truth", "Truth run must expose truth artifact mode.");
assert(string(S.PacketTraceSemantics) == "REAL_PACKET_TRAVERSAL", "Truth run must mark packet traces as real traversal.");
assert(contains(string(S.SummaryArtifact), "truth"), "Truth summary artifact name must include truth suffix.");
assert(contains(string(S.PacketTraceArtifact), "truth"), "Truth packet-trace artifact name must include truth suffix.");

runFolder = char(string(rep.Summary.RunFolder));
layout = sixgr.report.resultLayout(runFolder);
assert(exist(fullfile(layout.PacketFlowCSVDir, "probe_e2e_summary_truth.csv"), "file") == 2, ...
    "Missing truth summary artifact.");
assert(exist(fullfile(layout.PacketFlowCSVDir, "probe_e2e_qos_evaluation_truth.csv"), "file") == 2, ...
    "Missing truth QoS evaluation artifact.");
assert(exist(fullfile(layout.PacketFlowCSVDir, "probe_e2e_packet_integrity_truth.csv"), "file") == 2, ...
    "Missing truth packet-integrity artifact.");
assert(exist(fullfile(layout.PacketFlowCSVDir, "e2e_packet_trace_truth.csv"), "file") == 2, ...
    "Missing truth packet-trace artifact.");
assert(exist(fullfile(layout.PacketFlowCSVDir, "e2e_scheduler_trace_truth.csv"), "file") == 2, ...
    "Missing truth scheduler-trace artifact.");
assert(exist(fullfile(layout.PacketFlowCSVDir, "e2e_harq_trace_truth.csv"), "file") == 2, ...
    "Missing truth HARQ-trace artifact.");

ok = true;
end
