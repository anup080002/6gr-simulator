function testSourceAuditReproducesLegacyArtifactTypeFailure(testCase)
repositoryRoot = fileparts(fileparts(mfilename("fullpath")));
sourceAudit = fullfile(repositoryRoot,"results","lls", ...
    "lls_webgui_full_stack_sinr_geometry_qualification", ...
    "phase18_actual_20260729_01","reports","csv", ...
    "full_stack_artifact_audit.csv");
verifyTrue(testCase,isfile(sourceAudit), ...
    "The immutable Phase-18 source artifact audit is unavailable.");

audit = readtable(sourceAudit,"TextType","string", ...
    "VariableNamingRule","preserve");
verifyFalse(testCase,ismember("ArtifactType", ...
    string(audit.Properties.VariableNames)), ...
    "The source fixture must retain the schema that triggered the run.");

subcases = table(["SC-00";"SC-30"],[true;true], ...
    'VariableNames',{'SubcaseID','Executed'});
values = table();
components = table();
publication = table("PASS",'VariableNames',{'Status'});
regression = table(1,1,0,0,"PASS", ...
    'VariableNames',{'ExecutedTests','BlockedTests','SkippedTests', ...
    'FailedTests','Status'});
acceptance = table();

verifyError(testCase,@()localLegacyFinalizerAccess(audit), ...
    "MATLAB:table:UnrecognizedVarName");

result = sixgr.integration.qualification. ...
    QualificationFinalizationCoordinator.assess( ...
    subcases,values,components,audit,publication,regression,acceptance);
verifyEqual(testCase,string(result.ArtifactSchemaDiagnostic.Status),"PASS");
verifyEqual(testCase,height(result.CanonicalArtifactAudit),height(audit));
verifyTrue(testCase,all(ismember( ...
    result.CanonicalArtifactAudit.ArtifactType, ...
    sixgr.integration.qualification. ...
    QualificationArtifactAuditSchema.ArtifactTypes)));
verifyTrue(testCase,all(startsWith( ...
    result.CanonicalArtifactAudit.ArtifactTypeSource, ...
    "DERIVED_FROM_EXTENSION:")));
end

function testContradictoryTypeAliasesFailClosed(testCase)
audit = table("ART-1","figure.png","PNG","CSV",true,true,true,true, ...
    'VariableNames',{'ArtifactID','FileName','ArtifactType','FileType', ...
    'Present','SchemaValid','HashValid','SemanticValid'});
[canonical,diagnostic] = sixgr.integration.qualification. ...
    QualificationArtifactAuditNormalizer.normalize(audit);
verifyEmpty(testCase,canonical);
verifyEqual(testCase,string(diagnostic.Status),"FAIL");
verifyEqual(testCase,string(diagnostic.FailureCode), ...
    "FULLSTACK:ArtifactAuditSchemaInvalid");
end

function type = localLegacyFinalizerAccess(audit)
type = audit.ArtifactType;
end
