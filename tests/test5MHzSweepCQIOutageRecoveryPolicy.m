function ok=test5MHzSweepCQIOutageRecoveryPolicy()
%TEST5MHZSWEEPCQIOUTAGERECOVERYPOLICY Positive decoded CQI can schedule data.

setup6GRSimToolkit('Verbose',false);
scenarioPath=fullfile('simulator','configs','scenarios', ...
    'lls_tdd_5mhz_rank2_4tx2rx_awgn_m10db.yaml');
scfg=sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg=sixgr.lls6g.buildInternalConfig(scfg,tempname);

assert(double(cfg.phy.linkAdaptation.outageRecoveryPositiveCQIReports)==1, ...
    'test:5MHzSweepNonStandardCQIRecoveryGate', ...
    ['The 5 MHz physical sweep must not require multiple mutually similar ' ...
     'CRC-less CQI reports before attempting a robust data transmission.']);

[outage,state]=sixgr.link.computeLinkAdaptationDecision(cfg,'DL',struct( ...
    'CQI',0,'RI',1,'FeedbackAbsoluteSlot',24));
assert(~logical(outage.Valid) && ...
    string(outage.Reason)=="measured_cqi_zero_out_of_range", ...
    'CQI 0 must remain the TS 38.214 out-of-range state.');

[recovered,~]=sixgr.link.computeLinkAdaptationDecision(cfg,'DL',struct( ...
    'CQI',1,'RI',1,'FeedbackAbsoluteSlot',29), ...
    'AdaptationState',state);
assert(logical(recovered.Valid) && ...
    ~logical(recovered.CQIOutageRecoveryPending) && ...
    double(recovered.ResolvedCQI)==1 && ...
    isfinite(double(recovered.MCSIndex)) && ...
    double(recovered.MCSIndex)==0 && ...
    string(recovered.MCSSelectionSource)=="runtime_cqi_outage_recovery_filter", ...
    ['The first receiver-decoded positive CQI after outage must select the ' ...
     'installed robust CQI-1/MCS-0 point without using transmitted UCI bits.']);

fprintf('5MHZ_SWEEP_CQI_OUTAGE_RECOVERY_POLICY_PASS cqi=1 mcs=%g\n', ...
    double(recovered.MCSIndex));
ok=true;
end
