function ok = testObservedBLERCrossingResolution()
%TESTOBSERVEDBLERCROSSINGRESOLUTION Reject invented wide-bracket crossings.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

[status, crossing, info] = sixgr.validation.qualifyObservedBLERCrossing( ...
    [10; 20], [1; 0], 0.1, 2);
assert(status == "crossing_underresolved_bracket" && isnan(crossing), ...
    "A 10 dB BLER bracket must not be reported as a measured crossing.");
assert(info.BracketWidth_dB == 10 && ~info.InterpolationApplied, ...
    "The unresolved bracket must preserve its measured width and no interpolation.");

[status, crossing, info] = sixgr.validation.qualifyObservedBLERCrossing( ...
    [18; 19; 20], [0.4; 0.1; 0.02], 0.1, 2);
assert(status == "crossing_observed_exact_point" && crossing == 19 && ...
    info.BracketWidth_dB == 0, ...
    "An actually sampled target point must remain an exact crossing.");

[status, crossing, info] = sixgr.validation.qualifyObservedBLERCrossing( ...
    [18; 19; 20], [0.4; 0.2; 0.05], 0.1, 2);
expected = 19 + (0.1 - 0.2) / (0.05 - 0.2);
assert(status == "crossing_observed_interpolated" && ...
    abs(crossing - expected) < 1e-12 && info.InterpolationApplied, ...
    "Interpolation is valid only inside a sufficiently narrow measured bracket.");

fprintf("ObservedBLERCrossingResolution: PASS\n");
ok = true;
end
