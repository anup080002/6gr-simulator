function ok = testStrictControlChannelScenarioEvidence()
%TESTSTRICTCONTROLCHANNELSCENARIOEVIDENCE Verify scenario-level PDCCH/PUCCH waveform evidence.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

tmp = fullfile(pwd,'results','lls','strict_control_evidence', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(tmp);
fprintf('STRICT_CONTROL_EVIDENCE_ROOT=%s\n',tmp);

scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "lls_mobile_2ue_100kmh_1sector_full_capture.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, tmp);
% This is a bounded waveform/export regression, not a detector campaign.
% Install the explicit mini-anchor population design that the old mobile
% fixture predates. Keep every decode/export assertion and production guard.
mini=sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd,'configs','lls','lls_pdcch_strict_mini_anchor.yaml'));
design=mini.get('control.pdcch_strict');
for field=["validation_campaign","statistical_qualification"]
    cfg.phy.pdcch.operatorControl.pdcch_strict.(field)=design.(field);
    cfg.lls6g.control.pdcch_strict.(field)=design.(field);
end

evidence = sixgr.truth.exportStrictControlChannelEvidence(tmp, cfg, ...
    "RunId", "test_strict_control", ...
    "ScenarioName", string(scfg.ScenarioID), ...
    "EnablePDCCH", true, ...
    "EnablePUCCH", true);
if ~evidence.Ok && isfield(evidence.PDCCH,'ArtifactTables')
    diagnostic=evidence.PDCCH.ArtifactTables.pdcch_trials;
    disp(diagnostic(:,{'TrialId','TrialType','DCICrcPass','DCIPayloadMatch', ...
        'GrantValid','FalseCandidateCount','StrictOk','NegativeExpectedOk','FailureReason'}));
    disp(evidence.PDCCH.Config.StrictValidation);
end
assert(logical(evidence.Ok), "Strict scenario control evidence must pass for PDCCH and PUCCH: %s", ...
    char(evidence.FailureReason));

pdcchPath = fullfile(tmp, "air_interface", "csv", "pdcch_trials.csv");
pucchPath = fullfile(tmp, "air_interface", "csv", "pucch_trials.csv");
pdcchCandidatePath = fullfile(tmp, "control", "csv", "pdcch_candidates.csv");
pucchResourcePath = fullfile(tmp, "control", "csv", "pucch_resource_mapping.csv");
assert(exist(pdcchPath, "file") == 2, "Missing waveform-backed air-interface PDCCH trials.");
assert(exist(pucchPath, "file") == 2, "Missing waveform-backed air-interface PUCCH trials.");
assert(exist(pdcchCandidatePath, "file") == 2, "Missing PDCCH candidate/CCE evidence.");
assert(exist(pucchResourcePath, "file") == 2, "Missing PUCCH resource-mapping evidence.");

pdcch = readtable(pdcchPath, "VariableNamingRule", "preserve");
pucch = readtable(pucchPath, "VariableNamingRule", "preserve");
pdcchCand = readtable(pdcchCandidatePath, "VariableNamingRule", "preserve");
pucchRes = readtable(pucchResourcePath, "VariableNamingRule", "preserve");

assert(height(pdcch) >= 8 && height(pdcchCand) > height(pdcch), ...
    "PDCCH evidence must include strict trials plus multiple blind-decode candidates.");
assert(all(ismember(["CandidatesAttempted","DCICrcPass","TxCCEIndex","SelectedCCEIndex", ...
    "GrantValid","StrictOk","NegativeExpectedOk"], string(pdcch.Properties.VariableNames))), ...
    "PDCCH trials must expose blind-decode, CCE, CRC, and grant-validation evidence.");
assert(any(logical(pdcch.StrictOk)) && any(logical(pdcch.NegativeExpectedOk)), ...
    "PDCCH trials must include positive decodes and negative rejection evidence.");
wrong=pdcch(string(pdcch.TrialType)=="wrong_dci_format",:);
assert(height(wrong)==1 && wrong.DCICrcPass && ~wrong.GrantValid && ...
    wrong.NegativeExpectedOk && wrong.FalseCandidateCount==0, ...
    'Wrong-format semantic rejection must retain the actual CRC without authorizing a grant or inventing a false candidate.');
assert(isfinite(wrong.SelectedCCEIndex) && isfinite(wrong.SelectedAggregationLevel) && ...
    strlength(string(wrong.DCIPayloadHexRx))>0 && strlength(string(wrong.DCIPayloadHashRx))>0, ...
    'A later DCI schema rejection must not erase the measured candidate location or received payload.');
assert(~localTableContainsToken(pdcch, "available_runtime_abstraction"), ...
    "PDCCH waveform evidence must not carry runtime-abstraction labels.");

assert(height(pucch) >= 5 && height(pucchRes) == height(pucch), ...
    "PUCCH evidence must include measured trials and one resource mapping row per trial.");
assert(all(ismember(["PUCCHFormat","PUCCHPRBSet","PUCCHSymbolStart","PUCCHNumSymbols", ...
    "FrequencyHopping","PUCCHRECount","DMRSRECount","UCIContentMatch","DetectionMetric", ...
    "ExpectedBitCount","DecodedBitCount","UCIExpectedBitVector","UCIDecodedBitVector", ...
    "UCIBitErrorVector","UCICodedBitCount","UCICRCBitCount","UCICRCApplicable", ...
    "ReceiverHestSINRApplicable","GridHash","WaveformHash","StrictOk"], string(pucch.Properties.VariableNames))), ...
    "PUCCH trials must expose resource mapping, RE counts, UCI decode, UCI CRC, and waveform hashes.");
assert(all(logical(pucch.StrictOk)), "PUCCH strict waveform rows must pass.");
assert(any(double(pucch.PUCCHFormat) == 0) && any(double(pucch.PUCCHFormat) == 1) && ...
    any(double(pucch.PUCCHFormat) == 2), ...
    "PUCCH strict evidence must cover configured formats 0, 1, and 2.");
assert(any(double(pucch.DMRSRECount) > 0) && all(isfinite(double(pucch.PUCCHRECount))), ...
    "PUCCH evidence must include finite PUCCH RE counts and DMRS-backed rows.");
crcExpected = double(pucch.ExpectedBitCount) >= 12 & double(pucch.ResolvedFormat) >= 2;
assert(isequal(logical(pucch.UCICRCApplicable), crcExpected), ...
    "PUCCH CRC applicability must follow measured UCI payload length and resolved format.");
crcBitsExpected = zeros(height(pucch),1);
crcBitsExpected(crcExpected & double(pucch.ExpectedBitCount) <= 19) = 6;
crcBitsExpected(crcExpected & double(pucch.ExpectedBitCount) >= 20) = 11;
assert(isequal(double(pucch.UCICRCBitCount),crcBitsExpected), ...
    "TS 38.212 requires CRC6 for 12-19 UCI bits and CRC11 per code block for 20+ bits.");
assert(all(ismember([12 19 20],double(pucch.ExpectedBitCount))), ...
    'Physical export regression must exercise both UCI CRC boundaries.');
assert(all(isfinite(double(pucch.CRCPass(crcExpected)))) && ...
    all(~isfinite(double(pucch.CRCPass(~crcExpected)))), ...
    "PUCCH CRCPass must be populated only when UCI CRC is applicable.");
dmrsMask = double(pucch.DMRSRECount) > 0;
assert(isequal(logical(pucch.ReceiverHestSINRApplicable), dmrsMask), ...
    "PUCCH receiver Hest SINR applicability must be driven by actual DMRS RE presence.");
assert(all(isfinite(double(pucch.ReceiverHestSINR_dB(dmrsMask)))) && ...
    all(~isfinite(double(pucch.ReceiverHestSINR_dB(~dmrsMask)))), ...
    "PUCCH Hest SINR must be measured for DMRS-backed rows and blank for format-0/no-DMRS rows.");
paired = double(pucch.ExpectedBitCount)>0 & ...
    double(pucch.DecodedBitCount)==double(pucch.ExpectedBitCount);
assert(all(strlength(strtrim(string(pucch.UCIExpectedBitVector))) > 0) && ...
    all(strlength(strtrim(string(pucch.UCIBitErrorVector(paired)))) > 0) && ...
    all(string(pucch.BitComparisonStatus(paired))=="complete_equal_width_bit_comparison"), ...
    "Equal-width decoded PUCCH rows must export actual paired-bit errors.");
assert(any(~paired) && all(pucch.BitsCompared(~paired)==0) && ...
    all(isnan(pucch.BitErrors(~paired))) && ...
    all(ismissing(string(pucch.UCIBitErrorVector(~paired))) | ...
        strlength(strtrim(string(pucch.UCIBitErrorVector(~paired))))==0) && ...
    all(string(pucch.BitComparisonStatus(~paired))=="unavailable_no_decoded_bits") && ...
    all(pucch.DTXFlag(~paired)), ...
    'No-signal DTX must retain empty decoded/error vectors, not fabricated bit substitutions.');
assert(~localTableContainsToken(pucch, "available_runtime_abstraction"), ...
    "PUCCH waveform evidence must not carry runtime-abstraction labels.");

ok = true;
end

function tf = localTableContainsToken(T, token)
tf = false;
token = lower(string(token));
vars = string(T.Properties.VariableNames);
for i = 1:numel(vars)
    col = T.(vars(i));
    if isstring(col) || iscellstr(col) || ischar(col)
        values = lower(string(col));
        if any(contains(values(:), token))
            tf = true;
            return;
        end
    end
end
end
