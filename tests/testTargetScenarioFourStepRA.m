function ok = testTargetScenarioFourStepRA()
%TESTTARGETSCENARIOFOURSTEPRA Exercise the requested B4 RA/RRC waveform chain.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "webgui_sinr_sweep_64x4_mu_mimo_full.yaml");
scenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() localCleanup(tmp)); %#ok<NASGU>
cfg = sixgr.lls6g.buildInternalConfig(scenario, tmp);

result = sixgr.phy.ra.runFourStepRA(cfg, ...
    "RunFolder", tmp, ...
    "RunId", "target_b4_four_step_regression", ...
    "ScenarioName", "target_b4_four_step_regression", ...
    "UEId", 1, "CellId", 1, "WriteArtifacts", false, ...
    "RuntimeIntegrationMode", "coupled_truth_runtime", ...
    "RequireRuntimeStageWaveforms", true, ...
    "AllowRuntimeStageWaveformComposition", true, ...
    "UseRuntimeChannel", true, ...
    "RuntimeNoiseSNR_dB", 35, ...
    "RuntimeSlot", 10);

assert(logical(result.PreambleDetected), "Msg1 PRACH was not detected.");
assert(size(result.Msg1Tx.Waveform, 2) == 4, ...
    "YAML-authoritative four-element UE PRACH waveform was not propagated.");
assert(all(double(result.RuntimeStageRows.TxPortCount( ...
    result.RuntimeStageRows.Direction == "UL")) == 4), ...
    "UL four-step RA stages did not retain the configured four-port UE waveform domain.");
assert(logical(result.RuntimeChannelStateUsed), ...
    "The focused target RA regression did not exercise the persistent runtime channel.");
assert(logical(result.RuntimeNoiseApplied) && ...
    all(logical(result.RuntimeStageRows.NoiseApplied)) && ...
    all(abs(double(result.RuntimeStageRows.NoiseSNR_dB) - 35) < 1e-12), ...
    "Every Msg1-Msg4/RRC stage must consume the coupled operating-point SNR instead of the former infinite-SNR default.");
assert(logical(result.Msg2PDSCHCrcPass), "Msg2 RAR PDSCH CRC failed.");
assert(logical(result.Msg3PUSCHCrcPass), "Msg3 PUSCH CRC failed.");
assert(logical(result.Msg4PDSCHCrcPass), "Msg4 PDSCH CRC failed.");
assert(logical(result.RRCSetupCompleteDecoded) && ...
    logical(result.RRCConnected), ...
    "RRC Setup Complete did not traverse the SRB1/PUSCH waveform chain.");
assert(logical(result.RACompleted) && logical(result.StrictOk) && ...
    strlength(strtrim(string(result.FailureReason))) == 0, ...
    "Strict four-step RA did not complete cleanly: %s", ...
    string(result.FailureReason));
ok = true;
end

function localCleanup(pathText)
if isfolder(pathText)
    rmdir(pathText, "s");
end
end
