function ok = testLLSArtifactSanitizerSchemaIdempotency()
%TESTLLSARTIFACTSANITIZERSCHEMAIDEMPOTENCY Preserve required blank guards.

setup6GRSimToolkit("Verbose", false);
runFolder = string(tempname);
reportCSV = fullfile(runFolder, "reports", "csv");
mkdir(reportCSV);
cleanupObj = onCleanup(@() localRemoveTree(runFolder)); %#ok<NASGU>

Scope = ["run"; "ue"];
StrictOk = [true; true];
UsedOracleFields = [""; ""];
Notes = ["No oracle fields were consumed, strict waveform row."; ...
    "No oracle fields were consumed, strict waveform row."];
fixture = table(Scope, StrictOk, UsedOracleFields, Notes);
pathOut = fullfile(reportCSV, "schema_guard_fixture.csv");
sixgr.util.csvWriteTable(pathOut, fixture);

sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
roundTrip = readtable(pathOut, "FileType", "text", "Delimiter", ",", ...
    "ReadVariableNames", true, "VariableNamingRule", "preserve");
assert(all(ismember(["Scope","StrictOk","UsedOracleFields"], ...
    string(roundTrip.Properties.VariableNames))), ...
    "Repeated sanitization removed a contract-required blank oracle guard column.");
assert(all(string(roundTrip.Scope) == ["run"; "ue"]), ...
    "Repeated sanitization changed populated scope semantics.");

airCSV = fullfile(runFolder, "air_interface", "csv");
mkdir(airCSV);
ulTrial = table("run-1", "scenario-1", "abc123", "none", false, NaN, ...
    'VariableNames', {'RunID','ScenarioID','ConfigHash', ...
    'FrequencyHoppingMode','FrequencyHoppingApplied','SecondHopStartPRB'});
ulPath = fullfile(airCSV, "ul_pusch_trials.csv");
sixgr.util.csvWriteTable(ulPath, ulTrial, "PreserveSchema", true);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
ulFirstPassBytes = string(fileread(ulPath));
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
ulSecondPassBytes = string(fileread(ulPath));
ulRoundTrip = readtable(ulPath, "FileType", "text", "Delimiter", ",", ...
    "ReadVariableNames", true, "VariableNamingRule", "preserve");
assert(ismember("SecondHopStartPRB", string(ulRoundTrip.Properties.VariableNames)) && ...
    all(isnan(double(ulRoundTrip.SecondHopStartPRB))), ...
    "Canonical UL schema must retain an all-missing second-hop field when hopping is disabled.");
assert(string(ulRoundTrip.RunID(1)) == "run-1" && ...
    string(ulRoundTrip.ConfigHash(1)) == "abc123", ...
    "Canonical trial sanitization changed immutable runtime identity.");
assert(~contains(ulSecondPassBytes, "NaN") && ...
    ulFirstPassBytes == ulSecondPassBytes, ...
    "Declared all-missing fields must serialize as stable blanks, not literal NaN tokens.");

fixedTrial = table("DL", 20, "256QAM", NaN, missing, ...
    'VariableNames', {'Direction','MCSIndex','Modulation', ...
    'ScheduledMCSIndex','ScheduledModulation'});
fixedPath = fullfile(airCSV, "dl_fixed_link_campaign_trials.csv");
sixgr.util.csvWriteTable(fixedPath, fixedTrial, "PreserveSchema", true);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
fixedRaw = string(fileread(fixedPath));
fixedRoundTrip = readtable(fixedPath, "FileType", "text", "Delimiter", ",", ...
    "ReadVariableNames", true, "VariableNamingRule", "preserve");
assert(all(ismember(["ScheduledMCSIndex","ScheduledModulation"], ...
    string(fixedRoundTrip.Properties.VariableNames))), ...
    "Fixed-link recovery must retain declared scheduled-operating-point fields.");
assert(~contains(fixedRaw, "NaN"), ...
    "Fixed-link declared absent fields must remain blank rather than literal NaN.");

frcDiagnostic = table("dl_qpsk_awgn", 3.2, NaN, NaN, missing, ...
    'VariableNames', {'EntryId','RequiredSNR_dB','MeasuredSNR_dB', ...
    'Delta_dB','FailureIdentifier'});
frcDiagnosticPath = fullfile(reportCSV, "frc_reference_diagnostic.csv");
sixgr.util.csvWriteTable(frcDiagnosticPath, frcDiagnostic, "PreserveSchema", true);
frcLineage = table("frc_reference_point_dl_qpsk_awgn", ...
    "reports/image/dl_qpsk_awgn_reference_point.png", ...
    "reports/csv/frc_reference_points/dl_qpsk_awgn.csv", missing, ...
    'VariableNames', {'PlotId','ImagePath','SourceCSV','ImageSHA256'});
frcLineagePath = fullfile(reportCSV, "frc_reference_plot_lineage.csv");
sixgr.util.csvWriteTable(frcLineagePath, frcLineage, "PreserveSchema", true);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
frcDiagnosticRaw = string(fileread(frcDiagnosticPath));
frcLineageRaw = string(fileread(frcLineagePath));
frcDiagnosticRoundTrip = readtable(frcDiagnosticPath, "FileType", "text", ...
    "Delimiter", ",", "ReadVariableNames", true, "VariableNamingRule", "preserve");
frcLineageRoundTrip = readtable(frcLineagePath, "FileType", "text", ...
    "Delimiter", ",", "ReadVariableNames", true, "VariableNamingRule", "preserve");
assert(all(ismember(["MeasuredSNR_dB","Delta_dB","FailureIdentifier"], ...
    string(frcDiagnosticRoundTrip.Properties.VariableNames))), ...
    "FRC diagnostic recovery removed unresolved-but-required measurement fields.");
assert(ismember("ImageSHA256", string(frcLineageRoundTrip.Properties.VariableNames)), ...
    "FRC plot recovery removed the declared image-hash field before regeneration.");
assert(~contains(frcDiagnosticRaw, "NaN") && ~contains(frcLineageRaw, "NaN"), ...
    "Declared FRC absence must be a blank CSV cell, not a numeric-looking NaN token.");

ferT = table("run", "DL", 1, 0, 0, ...
    'VariableNames', {'Scope','Direction','ObservedFrames','ErroredFrames','FER'});
sixgr.util.csvWriteTable(fullfile(reportCSV, "fer_summary.csv"), ferT);
sixgr.truth.restoreCompletedRunTruthArtifacts(runFolder, struct());
ferMirror = readtable(fullfile(reportCSV, "live_error_rate_summary.csv"), ...
    "FileType", "text", "Delimiter", ",", "ReadVariableNames", true, ...
    "VariableNamingRule", "preserve");
assert(ismember("Scope", string(ferMirror.Properties.VariableNames)) && ...
    string(ferMirror.Scope(1)) == "run", ...
    "Completed-run recovery did not restore the FER mirror from its canonical runtime table.");

ok = true;
end

function localRemoveTree(pathValue)
if exist(pathValue, "dir") == 7
    rmdir(pathValue, "s");
end
end
