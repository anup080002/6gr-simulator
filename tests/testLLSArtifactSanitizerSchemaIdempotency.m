function ok = testLLSArtifactSanitizerSchemaIdempotency()
%TESTLLSARTIFACTSANITIZERSCHEMAIDEMPOTENCY Preserve required blank guards.

setup6GRSimToolkit("Verbose", false);
runFolder = string(tempname);
reportCSV = fullfile(runFolder, "reports", "csv");
mkdir(reportCSV);
cleanupObj = onCleanup(@() localRemoveTree(runFolder)); %#ok<NASGU>

Scope = ["run"; "ue"];
StrictOk = [true; true];
UsedOracleFields = [""; ""];
Notes = ["No oracle fields were consumed, strict waveform row."; ...
    "No oracle fields were consumed, strict waveform row."];
fixture = table(Scope, StrictOk, UsedOracleFields, Notes);
pathOut = fullfile(reportCSV, "schema_guard_fixture.csv");
sixgr.util.csvWriteTable(pathOut, fixture);

sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
roundTrip = readtable(pathOut, "FileType", "text", "Delimiter", ",", ...
    "ReadVariableNames", true, "VariableNamingRule", "preserve");
assert(all(ismember(["Scope","StrictOk","UsedOracleFields"], ...
    string(roundTrip.Properties.VariableNames))), ...
    "Repeated sanitization removed a contract-required blank oracle guard column.");
assert(all(string(roundTrip.Scope) == ["run"; "ue"]), ...
    "Repeated sanitization changed populated scope semantics.");

airCSV = fullfile(runFolder, "air_interface", "csv");
mkdir(airCSV);
ulTrial = table("run-1", "scenario-1", "abc123", "none", false, NaN, ...
    'VariableNames', {'RunID','ScenarioID','ConfigHash', ...
    'FrequencyHoppingMode','FrequencyHoppingApplied','SecondHopStartPRB'});
ulPath = fullfile(airCSV, "ul_pusch_trials.csv");
sixgr.util.csvWriteTable(ulPath, ulTrial, "PreserveSchema", true);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
ulFirstPassBytes = string(fileread(ulPath));
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
ulSecondPassBytes = string(fileread(ulPath));
ulRoundTrip = readtable(ulPath, "FileType", "text", "Delimiter", ",", ...
    "ReadVariableNames", true, "VariableNamingRule", "preserve");
assert(ismember("SecondHopStartPRB", string(ulRoundTrip.Properties.VariableNames)) && ...
    all(isnan(double(ulRoundTrip.SecondHopStartPRB))), ...
    "Canonical UL schema must retain an all-missing second-hop field when hopping is disabled.");
assert(string(ulRoundTrip.RunID(1)) == "run-1" && ...
    string(ulRoundTrip.ConfigHash(1)) == "abc123", ...
    "Canonical trial sanitization changed immutable runtime identity.");
assert(~contains(ulSecondPassBytes, "NaN") && ...
    ulFirstPassBytes == ulSecondPassBytes, ...
    "Declared all-missing fields must serialize as stable blanks, not literal NaN tokens.");

fixedTrial = table("DL", 20, "256QAM", NaN, missing, ...
    'VariableNames', {'Direction','MCSIndex','Modulation', ...
    'ScheduledMCSIndex','ScheduledModulation'});
fixedPath = fullfile(airCSV, "dl_fixed_link_campaign_trials.csv");
sixgr.util.csvWriteTable(fixedPath, fixedTrial, "PreserveSchema", true);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
fixedRaw = string(fileread(fixedPath));
fixedRoundTrip = readtable(fixedPath, "FileType", "text", "Delimiter", ",", ...
    "ReadVariableNames", true, "VariableNamingRule", "preserve");
assert(all(ismember(["ScheduledMCSIndex","ScheduledModulation"], ...
    string(fixedRoundTrip.Properties.VariableNames))), ...
    "Fixed-link recovery must retain declared scheduled-operating-point fields.");
assert(~contains(fixedRaw, "NaN"), ...
    "Fixed-link declared absent fields must remain blank rather than literal NaN.");

% A direction can have no transmissions at a low-SNR sweep point. Its
% undefined measurements must retain columns, not disappear during the
% finalizer after the initial writer already used PreserveSchema=true.
for prefix = ["DL","UL"]
    sweep = table(-10, 0, true, "NO_RUNTIME_TRIALS_AT_OPERATING_POINT", ...
        NaN, NaN, NaN, NaN, NaN, ...
        'VariableNames', cellstr(["SNR_dB", prefix+"_TrialCount", ...
        prefix+"_Incomplete", prefix+"_StopReason", prefix+"_BER", ...
        prefix+"_BLER", prefix+"_Goodput_Mbps", ...
        prefix+"_OfferedThroughput_Mbps", prefix+"_Throughput_Mbps"]));
    for name = ["lls_snr_sweep","lls_fixed_link_campaign", ...
            "lls_reference_snr_sweep","fixed_link_campaign_summary"]
        sweepPath = fullfile(airCSV, name+".csv");
        sixgr.util.csvWriteTable(sweepPath, sweep, "PreserveSchema", true);
        before = fileread(sweepPath);
        for pass = 1:2
            sixgr.truth.sanitizeLLSArtifactCSVs(runFolder, ...
                "OnlyPaths", sweepPath);
            assert(strcmp(before,fileread(sweepPath)), ...
                'Zero-attempt sweep columns and absence values must survive unchanged.');
        end
    end
end

harqCSV=fullfile(runFolder,"harq","csv");
mkdir(harqCSV);
pending=table("DL",1,"pending_tb",false,NaN,NaN,"", ...
    'VariableNames',{'Direction','SweepPointIndex','TBId','TransmitterTerminal', ...
    'TerminalAtSlot','FeedbackAck','TransmitterTerminalReason'});
pendingPath=fullfile(harqCSV,"harq_transmitter_lifecycle.csv");
sixgr.util.csvWriteTable(pendingPath,pending,"PreserveSchema",true);
pendingBytes=fileread(pendingPath);
for pass=1:2
    sixgr.truth.sanitizeLLSArtifactCSVs(runFolder,"OnlyPaths",pendingPath);
    assert(strcmp(pendingBytes,fileread(pendingPath)), ...
        'Pending HARQ rows must retain their unobserved terminal fields unchanged.');
end

frcDiagnostic = table("dl_qpsk_awgn", 3.2, NaN, NaN, missing, ...
    'VariableNames', {'EntryId','RequiredSNR_dB','MeasuredSNR_dB', ...
    'Delta_dB','FailureIdentifier'});
frcDiagnosticPath = fullfile(reportCSV, "frc_reference_diagnostic.csv");
sixgr.util.csvWriteTable(frcDiagnosticPath, frcDiagnostic, "PreserveSchema", true);
frcLineage = table("frc_reference_point_dl_qpsk_awgn", ...
    "reports/image/dl_qpsk_awgn_reference_point.png", ...
    "reports/csv/frc_reference_points/dl_qpsk_awgn.csv", missing, ...
    'VariableNames', {'PlotId','ImagePath','SourceCSV','ImageSHA256'});
frcLineagePath = fullfile(reportCSV, "frc_reference_plot_lineage.csv");
sixgr.util.csvWriteTable(frcLineagePath, frcLineage, "PreserveSchema", true);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
frcDiagnosticRaw = string(fileread(frcDiagnosticPath));
frcLineageRaw = string(fileread(frcLineagePath));
frcDiagnosticRoundTrip = readtable(frcDiagnosticPath, "FileType", "text", ...
    "Delimiter", ",", "ReadVariableNames", true, "VariableNamingRule", "preserve");
frcLineageRoundTrip = readtable(frcLineagePath, "FileType", "text", ...
    "Delimiter", ",", "ReadVariableNames", true, "VariableNamingRule", "preserve");
assert(all(ismember(["MeasuredSNR_dB","Delta_dB","FailureIdentifier"], ...
    string(frcDiagnosticRoundTrip.Properties.VariableNames))), ...
    "FRC diagnostic recovery removed unresolved-but-required measurement fields.");
assert(ismember("ImageSHA256", string(frcLineageRoundTrip.Properties.VariableNames)), ...
    "FRC plot recovery removed the declared image-hash field before regeneration.");
assert(~contains(frcDiagnosticRaw, "NaN") && ~contains(frcLineageRaw, "NaN"), ...
    "Declared FRC absence must be a blank CSV cell, not a numeric-looking NaN token.");

beamCSV = fullfile(runFolder, "beamforming", "csv");
mkdir(beamCSV);
% Exact applied matrices and their companion pattern schema must survive
% finalization. The absent context is legitimate for an independent PHY
% trial; pruning it used to round 1/sqrt(2) and invalidate MatrixSHA256.
W = complex([1/sqrt(2); 1/sqrt(2)], [0; 0]);
digest = string(sixgr.phy.mimo.MatrixContract.digest(W));
weights = table(repmat("numerical_serialization_fixture",2,1), ...
    strings(2,1),(0:1).',zeros(2,1),real(W),imag(W),repmat(digest,2,1), ...
    'VariableNames',{'TransmissionID','PHYGrantContextId','ElementIndex0', ...
    'LayerIndex0','WeightReal','WeightImag','MatrixSHA256'});
patterns = table("numerical_serialization_fixture","",digest,-Inf, ...
    'VariableNames',{'TransmissionID','PHYGrantContextId','MatrixSHA256','Directivity_dBi'});
for kind = ["weights","patterns"]
    exactPath = fullfile(beamCSV,"applied_data_precoder_"+kind+".csv");
    if kind=="weights", exactTable=weights; else, exactTable=patterns; end
    sixgr.util.csvWriteTable(exactPath,exactTable, ...
        'PreserveSchema',true,'RoundTripNumericText',true);
    exactBytes = fileread(exactPath);
    for pass=1:2
        sixgr.truth.sanitizeLLSArtifactCSVs(runFolder,'OnlyPaths',exactPath);
        sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
        sixgr.report.annotateScenarioCSVArtifacts(runFolder,"fixture","hash","test");
        assert(strcmp(exactBytes,fileread(exactPath)), ...
            'Applied matrix/pattern evidence must remain byte-identical after finalization.');
    end
end
roundWeights = sixgr.util.csvReadTable( ...
    fullfile(beamCSV,'applied_data_precoder_weights.csv'),'TextType','string');
assert(isequal(complex(roundWeights.WeightReal,roundWeights.WeightImag),W) && ...
    all(roundWeights.MatrixSHA256==sixgr.phy.mimo.MatrixContract.digest( ...
    complex(roundWeights.WeightReal,roundWeights.WeightImag))), ...
    'Finalized weights must reconstruct the authenticated matrix exactly.');
rankLayer = table("run-1", "DL", true, missing, ...
    'VariableNames', {'RunId','Direction','AdaptivePolicyConformance', ...
    'AdaptivePolicyFailureReason'});
rankLayerPath = fullfile(beamCSV, "rank_layer_trials.csv");
sixgr.util.csvWriteTable(rankLayerPath, rankLayer, "PreserveSchema", true);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
rankLayerRoundTrip = readtable(rankLayerPath, "FileType", "text", ...
    "Delimiter", ",", "ReadVariableNames", true, ...
    "VariableNamingRule", "preserve");
assert(ismember("AdaptivePolicyFailureReason", ...
    string(rankLayerRoundTrip.Properties.VariableNames)), ...
    "MIMO evidence sanitization removed the declared adaptive-policy failure field on passing rows.");

mimoLayer = table("run-1", 1, "DL", 1, NaN, NaN, ...
    'VariableNames', {'RunId','TrialId','Direction','LayerIndex', ...
    'ChannelEstimateNMSEdB','LLRMeanAbs'});
mimoLayerPath = fullfile(beamCSV, "mimo_layer_metrics.csv");
sixgr.util.csvWriteTable(mimoLayerPath, mimoLayer, "PreserveSchema", true);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
mimoLayerRoundTrip = readtable(mimoLayerPath, "FileType", "text", ...
    "Delimiter", ",", "ReadVariableNames", true, ...
    "VariableNamingRule", "preserve");
assert(all(ismember(["ChannelEstimateNMSEdB","LLRMeanAbs"], ...
    string(mimoLayerRoundTrip.Properties.VariableNames))), ...
    "MIMO layer sanitization removed declared unavailable per-layer metric columns.");

kpiManifest = table("run-1", "scenario-1", "DL", true, 1, missing, ...
    'VariableNames', {'RunId','ScenarioName','Direction','Exists','RowCount','FailureReason'});
kpiManifestPath = fullfile(reportCSV, "kpi_source_table_manifest.csv");
sixgr.util.csvWriteTable(kpiManifestPath, kpiManifest, "PreserveSchema", true);
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
kpiManifestRoundTrip = readtable(kpiManifestPath, "FileType", "text", ...
    "Delimiter", ",", "ReadVariableNames", true, ...
    "VariableNamingRule", "preserve");
assert(all(ismember(["ScenarioName","FailureReason"], ...
    string(kpiManifestRoundTrip.Properties.VariableNames))), ...
    "KPI evidence sanitization removed declared scenario or failure-reason fields.");

% The delivery ledger is an exact mirror of the attempt trace. Isolated
% waveform trials can legitimately lack a scheduler HARQ process identity.
% Sanitization must preserve the same unknown column in both directions,
% rather than silently deleting it from only the ledger.
for direction = ["dl","ul"]
    delivery = table("run-1",upper(direction),"tb-1",NaN,0,true,128,"", ...
        'VariableNames',{'RunId','Direction','TransportBlockId', ...
        'HARQProcessId','RV','FirstSuccessDelivery','CountedGoodputBits','FailureReason'});
    tracePath=fullfile(reportCSV,"kpi_harq_delivery_trace_"+direction+".csv");
    ledgerPath=fullfile(reportCSV,"kpi_tb_delivery_ledger_"+direction+".csv");
    sixgr.util.csvWriteTable(tracePath,delivery,"PreserveSchema",true);
    sixgr.util.csvWriteTable(ledgerPath,delivery,"PreserveSchema",true);
    sanitizedBytes="";
    for pass=1:2
        sixgr.truth.sanitizeLLSArtifactCSVs(runFolder, ...
            "OnlyPaths",[tracePath;ledgerPath]);
        assert(strcmp(fileread(tracePath),fileread(ledgerPath)), ...
            'Sanitization must preserve exact trace/ledger schema and values.');
        restored=sixgr.util.csvReadTable(ledgerPath);
        assert(ismember('HARQProcessId',restored.Properties.VariableNames) && ...
            all(isnan(sixgr.truth.numericMeasurementColumn(restored.HARQProcessId,'HARQProcessId'))) && ...
            restored.CountedGoodputBits==128, ...
            'Unknown HARQ identity and observed goodput must remain unchanged.');
        if pass==1
            sanitizedBytes=string(fileread(ledgerPath));
        else
            assert(sanitizedBytes==string(fileread(ledgerPath)), ...
                'Repeated ledger sanitization must be byte-idempotent.');
        end
    end
end

% A generic live-table canonicalizer runs before sanitizer schema retention.
% It must not drop unknown proxy/identity fields from an ordered HARQ
% projection, even when every row lacks those observations.
harqTimeline=table("DL","dl_raw_link_trials",1,NaN,"",NaN, ...
    'VariableNames',{'Direction','TraceSource','CRCPass', ...
    'DecoderTruthProxySINR_dB','TBId','SweepPointIndex'});
timelinePath=fullfile(harqCSV,"live_harq_observation_timeline.csv");
sixgr.util.csvWriteTable(timelinePath,harqTimeline,"PreserveSchema",true);
for pass=1:2
    sixgr.truth.sanitizeLLSArtifactCSVs(runFolder,"OnlyPaths",timelinePath);
    restored=sixgr.util.csvReadTable(timelinePath);
    assert(isequal(restored.Properties.VariableNames,harqTimeline.Properties.VariableNames), ...
        'Live HARQ canonicalization removed the declared observation schema.');
    assert(isnan(sixgr.truth.numericMeasurementColumn(restored.DecoderTruthProxySINR_dB,'DecoderTruthProxySINR_dB')) && ...
        isnan(sixgr.truth.numericMeasurementColumn(restored.SweepPointIndex,'SweepPointIndex')) && restored.CRCPass==1, ...
        'Missing HARQ evidence must not be replaced with finite measurements.');
end

metricCatalog = table("N", "harq_outputs", "HARQ outputs", ...
    "harq_process_timeline", "HARQ process timeline", "", "", ...
    "not_available", false, NaN, "", "count", "", "No HARQ rows.", ...
    'VariableNames', {'CategoryCode','CategoryKey','CategoryName', ...
    'MetricKey','MetricName','Entity','Statistic','Availability', ...
    'CountsTowardCoverage','ValueNumeric','ValueText','Unit', ...
    'SourceArtifact','Notes'});
metricCatalogPath = fullfile(reportCSV, "harq_outputs.csv");
sixgr.util.csvWriteTable(metricCatalogPath, metricCatalog, "PreserveSchema", true);
metricCatalogBytesBefore = string(fileread(metricCatalogPath));
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
metricCatalogBytesAfter = string(fileread(metricCatalogPath));
metricCatalogRoundTrip = readtable(metricCatalogPath, "FileType", "text", ...
    "Delimiter", ",", "ReadVariableNames", true, ...
    "VariableNamingRule", "preserve");
assert(width(metricCatalogRoundTrip) == 14 && ...
    all(ismember(["Entity","Statistic","ValueNumeric","ValueText","Unit"], ...
    string(metricCatalogRoundTrip.Properties.VariableNames))), ...
    "The global sanitizer must preserve the versioned 14-column metric catalog schema.");
assert(metricCatalogBytesBefore == metricCatalogBytesAfter, ...
    "The global sanitizer must not rewrite or type-coerce a versioned metric catalog.");

mixedMetricCatalog = [metricCatalog; metricCatalog];
mixedMetricCatalog.Statistic = ["numeric_rendering"; "histogram"];
mixedMetricCatalog.Availability = ["derived"; "observed"];
mixedMetricCatalog.CountsTowardCoverage = [true; true];
mixedMetricCatalog.ValueNumeric = [1; NaN];
mixedMetricCatalog.ValueText = ["1"; "rank1:120"];
mixedMetricCatalog.SourceArtifact = ["reports/csv/source.csv"; "reports/csv/source.csv"];
mixedPath = fullfile(reportCSV, "run_metadata_outputs.csv");
sixgr.util.csvWriteTable(mixedPath, mixedMetricCatalog, "PreserveSchema", true);
mixedBytesBefore = string(fileread(mixedPath));
sixgr.truth.sanitizeLLSArtifactCSVs(runFolder);
mixedBytesAfter = string(fileread(mixedPath));
assert(mixedBytesBefore == mixedBytesAfter && ...
    contains(mixedBytesAfter, '"rank1:120"'), ...
    "Metric sanitizer rewrote a heterogeneous ValueText column or replaced text with NaN.");

ferT = table("run", "DL", 1, 0, 0, ...
    'VariableNames', {'Scope','Direction','ObservedFrames','ErroredFrames','FER'});
sixgr.util.csvWriteTable(fullfile(reportCSV, "fer_summary.csv"), ferT);
sixgr.truth.restoreCompletedRunTruthArtifacts(runFolder, struct());
ferMirror = readtable(fullfile(reportCSV, "live_error_rate_summary.csv"), ...
    "FileType", "text", "Delimiter", ",", "ReadVariableNames", true, ...
    "VariableNamingRule", "preserve");
assert(ismember("Scope", string(ferMirror.Properties.VariableNames)) && ...
    string(ferMirror.Scope(1)) == "run", ...
    "Completed-run recovery did not restore the FER mirror from its canonical runtime table.");

ok = true;
end

function localRemoveTree(pathValue)
if exist(pathValue, "dir") == 7
    rmdir(pathValue, "s");
end
end
