function [ok,evidence] = testPDSCHFullBWPReferenceCharacterization(outputRoot)
%TESTPDSCHFULLBWPREFERENCECHARACTERIZATION Actual TX/scaler diagnostic only.
% Eighteen small, single-slot coded PDSCH transmissions: native frozen Type-I
% and explicitly declared I(:,1:r) / I(:,1:r)/sqrt(r), ranks 1/2/4, full and
% sparse frequency allocations. The full allocation is the carrier-sized BWP
% of these fixtures; narrower/offset BWPs and selective pages are NOT covered.
% No reference covariance is invented for untransmitted REs. A budget ratio
% is an OBSERVATION, not an assertion that a particular full-band reference
% policy is correct. No receiver, received DCI, channel, RF or radiation runs.
% Original operands and returned context are saved only to a new diagnostic
% MAT, never to primary study/report tables. Production scaling is unchanged.

setup6GRSimToolkit('Verbose',false);
previousRNG = rng;
restoreRNG = onCleanup(@() rng(previousRNG)); %#ok<NASGU>
if nargin < 1
    outputRoot = tempname(fullfile(fileparts(fileparts(mfilename('fullpath'))),'logs'));
end
assert(isscalar(string(outputRoot)) && strlength(string(outputRoot))>0 && ...
    ~isfile(outputRoot) && ~isfolder(outputRoot), ...
    'test:PDSCHPowerCharacterization:NewDestination', ...
    'Use a new diagnostic destination; existing evidence is never overwritten.');
mkdir(outputRoot);
fixture = 'simulator/configs/scenarios/lls_tdd_four_port_received_rank_transition_fixture.yaml';
scenario = sixgr.lls6g.config.loadScenarioConfig(fixture);
nativeCfg = sixgr.lls6g.buildInternalConfig(scenario,outputRoot);
[nativeCfg,~] = sixgr.phy.grid.applyRuntimeCarrierTimeline(nativeCfg,16,2);
scope = struct('EvidenceClass',"actual_PDSCH_TX_and_power_scaler_component", ...
    'ResearchClass',"optional_research_experiment", ...
    'ReferencePolicyQualified',false,'ReferenceCovarianceManufactured',false, ...
    'ReceivedControlExecuted',false,'ReceiverExecuted',false, ...
    'RFExecuted',false,'RadiationQualified',false,'HardwareQualified',false, ...
    'PrimaryStudyResult',false,'FixturePath',string(fixture), ...
    'FixtureSHA256',string(sixgr.util.sha256File(fixture)), ...
    'MATLABVersion',string(version),'MATLABRelease',string(version('-release')), ...
    'Interpretation',"Ratios characterize current actual scaling, not an agreed full-reference energy model.");
cases = cell(18,1);
checks = repmat(struct('Case',"",'Passed',false,'FailureID',"",'FailureReport',""),18,1);
index = 0;
for rankValue = [1 2 4]
    for allocation = ["full" "sparse"]
        for family = ["native_typeI" "explicit_I" "explicit_I_over_sqrt_rank"]
            index = index+1;
            name = family+"_rank"+rankValue+"_"+allocation;
            checks(index).Case = name;
            % Equal seeds for the two explicit matrix cases keep their TB,
            % modulation and layer operands identical; no output is altered.
            rng(63000+100*rankValue+double(allocation=="sparse"),'twister');
            beforeTX = rng;
            try
                [tx,txInfo,request] = localTransmit(nativeCfg,rankValue,allocation,family);
                cases{index} = struct('Case',name,'OriginalTX',tx, ...
                    'OriginalTxInfo',txInfo,'Request',request,'RNGImmediatelyBeforeTX',beforeTX);
                save(fullfile(outputRoot,'pdsch_full_bwp_power_diagnostic.mat'), ...
                    'scope','nativeCfg','checks','cases','-v7.3');
                cases{index} = localObserve(tx,txInfo,request,name,beforeTX);
                localCheck(cases{index});
                checks(index).Passed = true;
                fprintf('PDSCH_POWER_CHARACTERIZATION %s measured_budget_ratio=%.17g grid_energy_over_carrier_support=%.17g amplitude=%.17g\n', ...
                    name,cases{index}.Measured.OutputToDeclaredBudgetRatio, ...
                    cases{index}.Measured.GridEnergyOverCarrierActiveSupport, ...
                    cases{index}.PowerContext.AmplitudeScale);
            catch cause
                checks(index).FailureID = string(cause.identifier);
                checks(index).FailureReport = string(getReport(cause,'extended','hyperlinks','off'));
                fprintf(2,'PDSCH_POWER_CHARACTERIZATION %s FAIL %s\n',name,checks(index).FailureReport);
            end
            % Retain completed cases before later-case or comparison errors.
            save(fullfile(outputRoot,'pdsch_full_bwp_power_diagnostic.mat'), ...
                'scope','nativeCfg','checks','cases','-v7.3');
        end
    end
end
comparisons = localComparisons(cases,checks);
evidence = struct('Scope',scope,'OutputRoot',string(outputRoot), ...
    'Checks',struct2table(checks),'Cases',{cases},'Comparisons',comparisons);
save(fullfile(outputRoot,'pdsch_full_bwp_power_diagnostic.mat'), ...
    'scope','nativeCfg','checks','cases','comparisons','evidence','-v7.3');
assert(all([checks.Passed]),'test:PDSCHPowerCharacterization:ArithmeticOrSourceFailure', ...
    '%d/%d actual TX/scaler cases failed. Original diagnostics: %s', ...
    nnz(~[checks.Passed]),numel(checks),char(outputRoot));
assert(all(comparisons.ExplicitPairOperandsEqual), ...
    'test:PDSCHPowerCharacterization:PairInputsDiffer', ...
    'Explicit I and normalized-I comparisons require the same original layer/reference symbols.');
fprintf('PDSCH_FULL_BWP_CHARACTERIZATION_PASS actual_tx=%d receiver=0 reference_policy_qualified=0 folder=%s\n', ...
    numel(cases),char(outputRoot));
ok = true;
end

function [tx,info,request] = localTransmit(nativeCfg,r,allocation,family)
if family == "native_typeI"
    carrier = sixgr.phy.grid.makeCarrier(nativeCfg);
    assert(carrier.NSizeGrid<=25,'test:PDSCHPowerCharacterization:BoundedGrid', ...
        'This diagnostic is bounded to at most 25 PRBs.');
    prbs = localPRBs(carrier.NSizeGrid,allocation);
    [candidates,selection] = sixgr.phy.dl.pmiCodebookCandidates(nativeCfg,r,4);
    found = find([candidates.PMI]==0);
    assert(isscalar(found) && string(selection.NormalizationConvention)=="unit_frobenius");
    candidate = candidates(found);
    p = nativeCfg.phy.pdsch;
    grant = struct('Direction','DL','Frame',2,'Slot',16, ...
        'UEIndex',1,'RNTI',double(p.RNTI),'ServingCell',1, ...
        'PRBSet',prbs,'SymbolAllocation',double(p.symbolAllocation(:).'), ...
        'Modulation',p.modulation,'TargetCodeRate',double(p.codeRate), ...
        'MCSIndex',double(p.mcsIndex),'MCS',double(p.mcsIndex), ...
        'NumLayers',r,'Layers',r,'NumLogicalPorts',4, ...
        'PMI',0,'AppliedPrecoderPMI',0,'CRI',0, ...
        'PrecodingMatrix',[],'PrecodingActive',true,'K0',0, ...
        'GrantContextId',"declared_power_"+family+"_rank"+r+"_"+allocation, ...
        'HARQ',struct('HarqID',0,'NDI',true,'RV',0,'IsRetransmission',false));
    grant = withAuthoredPDSCHDCI(nativeCfg,grant); % TX fixture only, not reception.
    frozen = sixgr.phy.grant.freezePHYGrant(nativeCfg,'DL',grant);
    assert(isequaln(frozen.PrecodingState.PMICodebookMatrixCSIPorts,candidate.W));
    [tx,info] = sixgr.phy.dl.PDSCH_Tx(nativeCfg,'PHYGrant',frozen, ...
        'ExecutionProfile','phy_calibration','CompactOutput',false);
    assert(isequaln(tx.PHYGrant,frozen) && ...
        isequaln(tx.PrecodeInfo.MatrixPorts,frozen.PrecodingState.MatrixPhysicalPorts));
    request = struct('Family',family,'Rank',r,'Allocation',allocation, ...
        'PRBSet',prbs,'NativeCandidate',candidate,'OriginalGrant',grant, ...
        'FrozenGrant',frozen,'Matrix',frozen.PrecodingState.MatrixPhysicalPorts);
else
    W = eye(4,r);
    convention = "semi_unitary";
    if family == "explicit_I_over_sqrt_rank"
        W = W/sqrt(r); convention = "unit_frobenius";
    end
    [cfg,carrier,pdsch] = localCalibration(r,convention);
    pdsch.PRBSet = localPRBs(carrier.NSizeGrid,allocation);
    cfg.phy.pdsch.selectedPrecoderSHA256 = sixgr.phy.mimo.MatrixContract.digest(W);
    [tx,info] = sixgr.phy.dl.PDSCH_Tx(cfg,'Carrier',carrier,'PDSCH',pdsch, ...
        'PrecodingMatrix',W,'TargetCodeRate',0.30,'RV',0,'CompactOutput',false);
    assert(isequaln(tx.PrecodeInfo.MatrixPorts,W), ...
        'test:PDSCHPowerCharacterization:MatrixChanged', ...
        'The original explicit precoder must not be renormalized.');
    request = struct('Family',family,'Rank',r,'Allocation',allocation, ...
        'PRBSet',double(pdsch.PRBSet),'Matrix',W,'Config',cfg);
end
assert(isempty(tx.PDSCH.NSizeBWP) || tx.PDSCH.NSizeBWP==tx.Carrier.NSizeGrid, ...
    'test:PDSCHPowerCharacterization:UnsupportedBWP', ...
    'This fixture must retain a carrier-sized BWP; offset/narrow BWP is a separate domain.');
assert(isempty(tx.PDSCH.NStartBWP) || tx.PDSCH.NStartBWP==tx.Carrier.NStartGrid);
assert(isequal(double(tx.PDSCH.PRBSet(:).'),request.PRBSet) && ...
    tx.PDSCH.NumLayers==r && size(tx.Waveform,2)==4);
end

function prbs = localPRBs(count,allocation)
if allocation == "full"
    prbs = 0:double(count)-1;
else
    prbs = 0:2; % Three contiguous PRBs: real sparse allocation, no padded data.
end
assert(numel(prbs)<=count && (allocation=="full" || numel(prbs)<count));
end

function result = localObserve(tx,info,request,name,beforeTX)
% Independent declared physical scaler input, NOT inherited fixed-SNR mode.
% This does not change the TX request or pretend its samples already have an
% absolute calibration. The scaler alone establishes sqrt(mW) at its output.
powerCfg = struct();
powerCfg.run.noiseOperatingMode = 'receiver_noise_figure_thermal_noise';
powerCfg.powerAndRF.bsTxPower_dBm = 30;
powerCfg.powerAndRF.bsRFChainCount = 4;
powerCfg.powerAndRF.downlinkPowerNormalizationPolicy = 'fixed_epre_over_configured_bwp';
powerCfg.phy.carrier.NSizeGrid = double(tx.Carrier.NSizeGrid);
powerCfg.phy.carrier.SubcarrierSpacing = double(tx.Carrier.SubcarrierSpacing);
powerCfg.rf.pa.enable = false;
[scaled,ctx] = sixgr.rf.applyPowerContext(tx.Waveform,powerCfg,'DL',info,'ApplyPA',false);
grid = tx.Grid;
active = find(reshape(sum(abs(double(grid)).^2,[1 3]),[],1)>0);
assert(~isempty(active) && tx.OFDMWindowingSamples==0 && ...
    abs(double(info.OFDM.SampleRate)-double(info.OFDM.Nfft)*double(tx.Carrier.SubcarrierSpacing)*1000)<1e-6, ...
    'test:PDSCHPowerCharacterization:UnsupportedSampling', ...
    'Independent useful-sample arithmetic requires this unwindowed native-rate fixture.');
useful = localUsefulIndices(info.OFDM,size(grid,2),active,size(tx.Waveform,1));
inputPerPort = mean(abs(double(tx.Waveform(useful,:))).^2,1);
outputPerPort = mean(abs(double(scaled(useful,:))).^2,1);
recovered = nrOFDMDemodulate(tx.Carrier,scaled,'Nfft',double(info.OFDM.Nfft), ...
    'SampleRate',double(info.OFDM.SampleRate),'CyclicPrefixFraction',0.5);
assert(isequal(size(recovered),size(grid)));
flat = reshape(double(grid),[],size(grid,3));
flatRecovered = reshape(double(recovered),[],size(grid,3));
data = double(tx.ResourcePlan.DataIndices(:))+1;
assert(~isempty(data) && numel(unique(data))==numel(data));
E = sum(abs(double(grid(:,active,:))).^2,'all');
S = double(tx.PDSCHLayerSymbols);
X = double(tx.PDSCHPortSymbols);
measured = struct('ActiveSymbolsZeroBased',double(active(:)-1), ...
    'UsefulSampleIndicesOneBased',useful,'UsefulTimeSampleCount',numel(useful), ...
    'InputPerPortPower_native_sample_squared',inputPerPort, ...
    'InputTotalPower_native_sample_squared',sum(inputPerPort), ...
    'OutputPerPortPower_mW',outputPerPort,'OutputTotalPower_mW',sum(outputPerPort), ...
    'DeclaredBudget_mW',10^(powerCfg.powerAndRF.bsTxPower_dBm/10), ...
    'OutputToDeclaredBudgetRatio',sum(outputPerPort)/10^(powerCfg.powerAndRF.bsTxPower_dBm/10), ...
    'CompositeActiveGridEnergy',E,'CarrierActiveTFCount',size(grid,1)*numel(active), ...
    'GridEnergyOverCarrierActiveSupport',E/(size(grid,1)*numel(active)), ...
    'OutputBudgetRatioMinusUnitTotalREFormula', ...
        sum(outputPerPort)/10^(powerCfg.powerAndRF.bsTxPower_dBm/10)-E/(size(grid,1)*numel(active)), ...
    'DataTFCount',numel(data), ...
    'DataGridEnergyBeforeScale',sum(abs(flat(data,:)).^2,'all'), ...
    'DataEPREAfterScale_sum_over_ports',mean(sum(abs(flatRecovered(data,:)).^2,2)), ...
    'DataLayerUncenteredCovariance',S.'*conj(S)/size(S,1), ...
    'DataPortUncenteredCovariance',X.'*conj(X)/size(X,1), ...
    'MatrixGram',request.Matrix'*request.Matrix, ...
    'MatrixFrobeniusPower',sum(abs(request.Matrix).^2,'all'), ...
    'DemodulatedScaledGrid',recovered, ...
    'DemodulatedGridMaxAbsError',max(abs(double(recovered)-double(grid).*ctx.AmplitudeScale),[],'all'));
original = struct('Carrier',tx.Carrier,'PDSCH',tx.PDSCH, ...
    'Grid',grid,'Waveform',tx.Waveform,'LayerSymbols',tx.PDSCHLayerSymbols, ...
    'PortSymbols',tx.PDSCHPortSymbols,'ResourcePlan',tx.ResourcePlan, ...
    'PrecoderBundle',tx.PrecoderBundle,'DataPrecoderTrace',tx.DataPrecoderTrace, ...
    'DMRSPrecoderTrace',tx.DMRSPrecoderTrace,'PTRSPrecoderTrace',tx.PTRSPrecoderTrace, ...
    'ReferenceConfig',tx.ReferenceConfig,'ReferenceSignals',tx.ReferenceSignals, ...
    'ResourceAccounting',tx.ResourceAccounting,'PrecodePowerInfo',tx.PrecodePowerInfo, ...
    'ScalerTxInfo',info,'RNGImmediatelyBeforeTX',beforeTX);
result = struct('Case',name,'Request',request,'Original',original, ...
    'PowerConfig',powerCfg,'ScaledWaveform',scaled,'PowerContext',ctx, ...
    'Measured',measured,'ReferencePolicyQualified',false);
end

function indices = localUsefulIndices(ofdm,L,active,nSamples)
nfft = double(ofdm.Nfft);
cp = double(ofdm.CyclicPrefixLengths(:));
assert(nfft>0 && nfft==fix(nfft) && numel(cp)>=L && ...
    all(cp>=0 & cp==fix(cp)));
offsets = [0;cumsum(cp(1:L-1)+nfft)];
indices = zeros(nfft*numel(active),1);
for k = 1:numel(active)
    symbol = active(k);
    indices((k-1)*nfft+(1:nfft)) = offsets(symbol)+cp(symbol)+(1:nfft).';
end
assert(max(indices)<=nSamples && numel(unique(indices))==numel(indices));
end

function localCheck(c)
ctx = c.PowerContext; m = c.Measured; o = c.Original;
assert(~ctx.FixedSNRNormalizedReference && ctx.ScaleApplied && ~ctx.PAApplied && ...
    string(ctx.WaveformAmplitudeUnit)=="sqrt_mW" && ...
    string(ctx.PowerNormalizationPolicy)=="fixed_epre_over_configured_bwp");
assert(isequaln(c.ScaledWaveform,o.Waveform.*cast(ctx.AmplitudeScale,'like',o.Waveform)) && ...
    isequaln(o.ScalerTxInfo.TxContext.PortGrid,o.Grid) && ...
    isequaln(o.ScalerTxInfo.TxContext.Waveform,o.Waveform));
localClose(m.InputTotalPower_native_sample_squared,ctx.InputTotalPower_mW);
localClose(m.OutputTotalPower_mW,ctx.OutputTotalPower_mW);
localClose(m.OutputPerPortPower_mW,ctx.OutputPerPortPower_mW);
assert(ctx.ReferenceSampleCount==m.UsefulTimeSampleCount*size(o.Waveform,2));
localClose(m.OutputTotalPower_mW,m.InputTotalPower_native_sample_squared*ctx.AmplitudeScale^2);
localClose(m.DemodulatedScaledGrid,double(o.Grid).*ctx.AmplitudeScale);
% Context must describe its actual application. Do NOT assert that activity
% equals E/(K*L), or that full allocation equals the declared budget: those
% ratios are retained separately to characterize the unresolved reference.
localClose(m.OutputToDeclaredBudgetRatio,ctx.FullBWPActivityFactor);
assert(ctx.NormalizationGridSubcarrierCount==size(o.Grid,1) && ...
    ctx.NormalizationGridActiveSymbolCount==numel(m.ActiveSymbolsZeroBased));
localClose(o.PortSymbols,double(o.LayerSymbols)*c.Request.Matrix.');
localClose(m.DataPortUncenteredCovariance, ...
    c.Request.Matrix*m.DataLayerUncenteredCovariance*c.Request.Matrix');
end

function localClose(actual,expected)
% Floating-point transform/summation check only, not an RF or power limit.
assert(isequal(size(actual),size(expected)) && all(isfinite(actual),'all') && ...
    all(isfinite(expected),'all') && ...
    max(abs(double(actual)-double(expected)),[],'all') <= ...
    2e-10*max(1,max(abs(double(expected)),[],'all')), ...
    'test:PDSCHPowerCharacterization:ArithmeticMismatch', ...
    'Original sample/grid/context arithmetic did not close.');
end

function T = localComparisons(cases,checks)
rows = repmat(struct('Rank',NaN,'Allocation',"", ...
    'ExplicitPairOperandsEqual',false,'I_OutputBudgetRatio',NaN, ...
    'NormalizedI_OutputBudgetRatio',NaN,'MeasuredOutputRatio_I_over_NormalizedI',NaN, ...
    'ReferencePolicyQualified',false),0,1);
for r = [1 2 4]
    for allocation = ["full" "sparse"]
        i = find(string({checks.Case})=="explicit_I_rank"+r+"_"+allocation);
        j = find(string({checks.Case})=="explicit_I_over_sqrt_rank_rank"+r+"_"+allocation);
        if ~checks(i).Passed || ~checks(j).Passed, continue; end
        a = cases{i}; b = cases{j};
        equal = isequaln(a.Original.LayerSymbols,b.Original.LayerSymbols) && ...
            isequaln(a.Original.ReferenceSignals,b.Original.ReferenceSignals) && ...
            isequaln(a.Original.ResourcePlan.DataIndices,b.Original.ResourcePlan.DataIndices);
        rows(end+1,1) = struct('Rank',r,'Allocation',allocation, ...
            'ExplicitPairOperandsEqual',equal, ...
            'I_OutputBudgetRatio',a.Measured.OutputToDeclaredBudgetRatio, ...
            'NormalizedI_OutputBudgetRatio',b.Measured.OutputToDeclaredBudgetRatio, ...
            'MeasuredOutputRatio_I_over_NormalizedI',a.Measured.OutputTotalPower_mW/b.Measured.OutputTotalPower_mW, ...
            'ReferencePolicyQualified',false); %#ok<AGROW>
    end
end
T = struct2table(rows);
end

