def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--compiled-module", required=True, type=Path)
    parser.add_argument("--source-spec", required=True, type=Path)
    parser.add_argument("--catalog", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    module = load_module(args.compiled_module)
    definitions = module.NR_RRC_Definitions
    definitions.CellGroupConfig.set_val({"cellGroupId": 0})
    master_cell_group = definitions.CellGroupConfig.to_uper()
    source_hash = sha256(args.source_spec)
    generator_hash = sha256(Path(__file__))

    with args.catalog.open(newline="", encoding="utf-8-sig") as source:
        catalog = list(csv.DictReader(source))
    output = []
    for source_row in catalog:
        if source_row["ExpectedValid"].lower() != "true":
            continue
        message_type = source_row["MessageType"]
        transaction_id = int(source_row["TransactionID"])
        wrapper_name, channel, alternative = CHANNELS[message_type]
        value = message_value(message_type, transaction_id, master_cell_group)
        wrapper_value = {"message": ("c1", (alternative, value))}
        wrapper = getattr(definitions, wrapper_name)
        wrapper.set_val(wrapper_value)
        encoded = wrapper.to_uper()
        wrapper.from_uper(encoded)
        decoded = wrapper.get_val()
        decoded_json = json.dumps(
            canonical(decoded), sort_keys=True, separators=(",", ":")
        )
        vector_identity = "|".join(
            [
                source_row["CaseID"],
                message_type,
                str(transaction_id),
                channel,
                encoded.hex().upper(),
                decoded_json,
                source_hash,
            ]
        )
        output.append(
            {
                "CaseID": source_row["CaseID"],
                "MessageType": message_type,
                "TransactionID": transaction_id,
                "Channel": channel,
                "ASN1Release": "38.331-v18.9.0",
                "UPERHex": encoded.hex().upper(),
                "EncodedBits": len(encoded) * 8,
                "DecodedTreeJSON": decoded_json,
                "DecodedTreeSHA256": hashlib.sha256(
                    decoded_json.encode("utf-8")
                ).hexdigest(),
                "OracleImplementation": "pycrate_asn1c+pycrate_asn1rt",
                "OracleVersion": "0.7.11",
                "SpecificationSourceSHA256": source_hash,
                "GeneratorSHA256": generator_hash,
                "VectorSHA256": hashlib.sha256(
                    vector_identity.encode("utf-8")
                ).hexdigest(),
            }
        )

    columns = list(output[0])
    with args.output.open("w", newline="", encoding="utf-8") as target:
        writer = csv.DictWriter(target, fieldnames=columns)
        writer.writeheader()
        writer.writerows(output)
    print(
        json.dumps(
            {
                "vectors": len(output),
                "specification_source_sha256": source_hash,
                "output_sha256": sha256(args.output),
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
