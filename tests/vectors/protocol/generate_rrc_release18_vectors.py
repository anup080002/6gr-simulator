#!/usr/bin/env python3
"""Generate frozen connected-mode UPER vectors with independent pycrate.

The input module must be generated by pycrate_asn1c from the official
3GPP TS 38.331 V18.9.0 ASN.1 segments.  This generator intentionally lives
outside the MATLAB implementation under test.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import importlib.util
import json
from pathlib import Path
from typing import Any


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def canonical(value: Any) -> Any:
    if isinstance(value, bytes):
        return {"octets_hex": value.hex().upper()}
    if isinstance(value, tuple):
        if len(value) == 2 and isinstance(value[0], str):
            return {"choice": value[0], "value": canonical(value[1])}
        if len(value) == 2 and all(isinstance(item, int) for item in value):
            return {"bit_string_value": value[0], "bit_length": value[1]}
        return [canonical(item) for item in value]
    if isinstance(value, dict):
        return {key: canonical(value[key]) for key in sorted(value)}
    if isinstance(value, list):
        return [canonical(item) for item in value]
    return value


def load_module(path: Path):
    spec = importlib.util.spec_from_file_location("sixgr_rrc_nr_v1890", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Unable to import compiled ASN.1 module {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def transaction(message_type: str, transaction_id: int, mcg: bytes) -> dict:
    empty = {
        "SecurityModeComplete": ("securityModeComplete", {}),
        "UECapabilityInformation": ("ueCapabilityInformation", {}),
        "RRCReconfiguration": ("rrcReconfiguration", {}),
        "RRCReconfigurationComplete": ("rrcReconfigurationComplete", {}),
        "RRCRelease": ("rrcRelease", {}),
        "RRCReestablishmentComplete": ("rrcReestablishmentComplete", {}),
        "RRCResume": ("rrcResume", {}),
        "RRCResumeComplete": ("rrcResumeComplete", {}),
    }
    if message_type in empty:
        choice, ies = empty[message_type]
    elif message_type == "RRCSetup":
        choice = "rrcSetup"
        ies = {"radioBearerConfig": {}, "masterCellGroup": mcg}
    elif message_type == "RRCSetupComplete":
        choice = "rrcSetupComplete"
        ies = {
            "selectedPLMN-Identity": 1,
            "dedicatedNAS-Message": b"\x01",
        }
    elif message_type == "SecurityModeCommand":
        choice = "securityModeCommand"
        ies = {
            "securityConfigSMC": {
                "securityAlgorithmConfig": {
                    "cipheringAlgorithm": "nea2",
                    "integrityProtAlgorithm": "nia2",
                }
            }
        }
    elif message_type == "UECapabilityEnquiry":
        choice = "ueCapabilityEnquiry"
        ies = {"ue-CapabilityRAT-RequestList": [{"rat-Type": "nr"}]}
    elif message_type == "RRCReestablishment":
        choice = "rrcReestablishment"
        ies = {"nextHopChainingCount": 0}
    else:
        raise KeyError(message_type)
    return {
        "rrc-TransactionIdentifier": transaction_id,
        "criticalExtensions": (choice, ies),
    }


def message_value(message_type: str, transaction_id: int, mcg: bytes) -> dict:
    if message_type == "RRCSetupRequest":
        return {
            "rrcSetupRequest": {
                "ue-Identity": ("randomValue", (0x123456789, 39)),
                "establishmentCause": "mo-Data",
                "spare": (0, 1),
            }
        }
    if message_type == "MeasurementReport":
        return {
            "criticalExtensions": (
                "measurementReport",
                {
                    "measResults": {
                        "measId": 1,
                        "measResultServingMOList": [
                            {
                                "servCellId": 0,
                                "measResultServingCell": {
                                    "measResult": {"cellResults": {}}
                                },
                            }
                        ],
                    }
                },
            )
        }
    if message_type == "RRCReestablishmentRequest":
        return {
            "rrcReestablishmentRequest": {
                "ue-Identity": {
                    "c-RNTI": 1,
                    "physCellId": 0,
                    "shortMAC-I": (0, 16),
                },
                "reestablishmentCause": "otherFailure",
                "spare": (0, 1),
            }
        }
    if message_type == "RRCResumeRequest":
        return {
            "rrcResumeRequest": {
                "resumeIdentity": (0x123456, 24),
                "resumeMAC-I": (0, 16),
                "resumeCause": "mo-Data",
                "spare": (0, 1),
            }
        }
    return transaction(message_type, transaction_id, mcg)


