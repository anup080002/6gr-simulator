function ok = testRFImpairmentOrderedChain()
%TESTRFIMPAIRMENTORDEREDCHAIN Numerical anchors for ordered RF impairments.

setup6GRSimToolkit("Verbose", false);

fs = 1000;
rs = RandStream("mt19937ar", "Seed", 14014);
x = complex(randn(rs, 128, 2), randn(rs, 128, 2)) / sqrt(2);

cfg = struct();
identity = sixgr.rf.applyRFImpairmentChain(x, cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "rx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", false, ...
    "ApplyPA", false, ...
    "ApplyADC", false);
assert(localMaxAbs(identity.Waveform - x) == 0, ...
    "Disabled RF chain must be sample-exact identity.");
assert(logical(identity.Replay.RFDisabledIdentity), ...
    "Disabled RF chain must be reported as an identity transform.");
assert(identity.Replay.RFConfiguredStageCount == 0 && identity.Replay.RFAppliedStageCount == 0, ...
    "Disabled RF chain must not mark configured or applied stages.");

cfg = struct();
cfg.rf.rx.cfo_Hz = 125;
cfo = sixgr.rf.applyRFImpairmentChain(ones(64, 1), cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "rx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyADC", false);
n = (0:63).';
expectedCFO = exp(1j * 2 * pi * cfg.rf.rx.cfo_Hz / fs .* n);
assert(localMaxAbs(cfo.Waveform - expectedCFO) < 1e-12, ...
    "CFO stage must implement x[n]exp(j2pi f_off n/Fs).");
assert(abs(double(cfo.Replay.InjectedCFO_Hz) - 125) < 1e-12 && logical(cfo.Replay.CFOApplied), ...
    "CFO replay must disclose the injected/applied offset.");
rowCFO = cfo.StageTrace(string(cfo.StageTrace.StageName) == "rx_lo_cfo", :);
assert(abs(double(rowCFO.PowerDelta_dB)) < 1e-12, ...
    "Pure CFO rotation must conserve sample power.");

cfg.rf.rx.cfo_Hz = -75;
cfoNeg = sixgr.rf.applyRFImpairmentChain(ones(64, 1), cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "rx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyADC", false);
expectedCFONeg = exp(1j * 2 * pi * cfg.rf.rx.cfo_Hz / fs .* n);
assert(localMaxAbs(cfoNeg.Waveform - expectedCFONeg) < 1e-12, ...
    "Negative CFO must use the same signed oscillator equation.");
assert(abs(double(cfoNeg.Replay.InjectedCFO_Hz) + 75) < 1e-12, ...
    "Negative CFO replay must preserve the injected sign.");

cfg = struct();
cfg.rf.rx.timingOffsetSamples = -0.375;
timing = sixgr.rf.applyRFImpairmentChain(x, cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "rx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyADC", false);
expectedTiming = sixgr.util.applyFractionalSampleDelay(x, -0.375);
assert(localMaxAbs(timing.Waveform - expectedTiming) < 1e-12, ...
    "Standalone timing impairment must use the fractional-delay operator.");
assert(abs(double(timing.Replay.InjectedTimingOffset_samples) + 0.375) < 1e-12 && ...
        logical(timing.Replay.TimingOffsetApplied), ...
    "Timing replay must disclose the exact signed fractional-sample offset.");

cfg = struct();
cfg.rf.rx.sampleClockOffset.enable = true;
cfg.rf.rx.sampleClockOffset.ppm = 1000;
ramp = complex((0:15).', zeros(16, 1));
sco = sixgr.rf.applyRFImpairmentChain(ramp, cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "rx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyADC", false);
referenceResampler = sixgr.rf.runtime.StatefulSampleRateOffsetResampler( ...
    1, 1000, 0.4, 1);
[expectedSCO, scoTrace] = referenceResampler.process(ramp, ...
    "PreserveLength", true);
assert(localMaxAbs(sco.Waveform - expectedSCO) < 1e-12, ...
    "Live sample-clock offset must use the canonical stateful bandlimited resampler.");
assert(all(isfinite(sco.Waveform), "all") && ...
        strcmp(string(scoTrace.Interpolation), ...
        "stateful_cubic_farrow_with_fir_antialias"), ...
    "Sample-clock resampling must disclose finite, anti-aliased Farrow output.");
assert(logical(sco.Replay.SampleClockOffsetApplied) && ...
        abs(double(sco.Replay.SampleClockOffsetPpm) - 1000) < 1e-12, ...
    "SCO replay must mark applied resampling and preserve ppm.");

cfg = struct();
cfg.rf.rx.iqImbalance.enable = true;
cfg.rf.rx.iqImbalance.gainImbalance_dB = 1.5;
cfg.rf.rx.iqImbalance.phaseImbalance_deg = 7;
iq = sixgr.rf.applyRFImpairmentChain(x, cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "rx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyADC", false);
expectedIQ = localIQModel(x, 1.5, 7);
assert(localMaxAbs(iq.Waveform - expectedIQ) < 1e-12, ...
    "IQ imbalance must implement alpha*x + beta*conj(x).");
assert(logical(iq.Replay.IQImbalanceApplied), ...
    "IQ replay must mark the stage as applied.");
[alpha, beta] = localIQAlphaBeta(1.5, 7);
expectedIRR = 20 * log10(abs(alpha) / abs(beta));
assert(abs(double(iq.Replay.IQImbalanceImageRejection_dB) - expectedIRR) < 0.25, ...
    "IQ image-rejection measurement must match the alpha/beta analytical ratio.");

cfg = struct();
cfg.rf.pa.enable = true;
cfg.rf.pa.method = "softlimiter";
cfg.rf.pa.backoff_dB = 0;
xPA = complex([0.1; 0.5; 1; 2], [0.2; -0.1; 0.3; -0.4]);
pa = sixgr.rf.applyRFImpairmentChain(xPA, cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "tx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyPA", true, ...
    "ApplyADC", false);
expectedPA = xPA ./ sqrt(1 + abs(xPA).^4);
assert(localMaxAbs(pa.Waveform - expectedPA) < 1e-12, ...
    "Soft-limiter PA must follow the configured AM/AM equation.");
rowPA = pa.StageTrace(string(pa.StageTrace.StageName) == "tx_pa", :);
expectedDelta = 10 * log10(mean(abs(expectedPA(:)).^2) / mean(abs(xPA(:)).^2));
assert(abs(double(rowPA.PowerDelta_dB) - expectedDelta) < 1e-12, ...
    "PA stage ledger must close to measured before/after power.");
expectedEVM = 100 * rms(abs(expectedPA(:) - xPA(:))) / rms(abs(xPA(:)));
assert(abs(double(pa.Row.EVMMeasuredPercent) - expectedEVM) < 1e-12, ...
    "PA clipping EVM must be measured from the actual before/after samples.");

cfg.rf.pa.method = "memorypolynomial";
cfg.rf.pa.memory.enable = true;
cfg.rf.pa.memory.taps = [1 0.25];
cfg.rf.pa.memory.orders = [1 3];
cfg.rf.pa.memory.orderWeights = [1 -0.1];
xMem = complex([1; 2; 0; -1], [0; 0; 0; 0]);
paMem = sixgr.rf.applyRFImpairmentChain(xMem, cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "tx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyPA", true, ...
    "ApplyADC", false);
expectedMem = localMemoryPolynomial(xMem, [1 0.25], [1 3], [1 -0.1]);
assert(localMaxAbs(paMem.Waveform - expectedMem) < 1e-12, ...
    "Memory-polynomial PA must include delayed circuit-memory taps.");

cfg = struct();
cfg.rf.rx.agc.enable = true;
cfg.rf.rx.agc.targetRms = 0.5;
cfg.rf.rx.agc.maxGain_dB = 40;
cfg.rf.rx.agc.minGain_dB = -40;
cfg.rf.adc.enable = true;
cfg.rf.adcBits = 4;
cfg.rf.adc.fullScale = 1;
xAdc = complex([0.05; 0.10; -0.05; -0.10], zeros(4, 1));
adc = sixgr.rf.applyRFImpairmentChain(xAdc, cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "rx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyADC", true);
agcGain = 0.5 / rms(abs(xAdc));
expectedADCIn = xAdc .* agcGain;
expectedADC = localQuantize(expectedADCIn, 4, 1);
assert(localMaxAbs(adc.Waveform - expectedADC) < 1e-12, ...
    "AGC must scale to target RMS before calibrated full-scale ADC quantization.");
assert(abs(double(adc.Replay.AGCGain_dB) - 20 * log10(agcGain)) < 1e-12 && ...
        abs(double(adc.Replay.ADCFullScale) - 1) < 1e-12, ...
    "AGC/ADC replay must disclose gain and calibrated full scale.");

cfg = struct();
cfg.rf.rx.element.enable = true;
cfg.rf.rx.element.gain_dB = [0 6];
cfg.rf.rx.element.phase_deg = [0 90];
xElem = complex(ones(8, 2), zeros(8, 2));
elem = sixgr.rf.applyRFImpairmentChain(xElem, cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "rx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyADC", false);
expectedElem = xElem .* [1, 10^(6/20) * 1j];
assert(localMaxAbs(elem.Waveform - expectedElem) < 1e-12, ...
    "Element-domain RF gain/phase must apply per waveform element column.");
assert(logical(elem.Replay.ElementRFApplied), ...
    "Element RF replay must mark applied per-element analog impairment.");

cfg = struct();
cfg.rf.rx.element.enable = true;
cfg.rf.rx.element.mutualCoupling.enable = true;
cfg.rf.rx.element.mutualCoupling.matrix = [1 0.25; -0.5 1];
xCouple = complex([1 0; 0 1], zeros(2, 2));
coupled = sixgr.rf.applyRFImpairmentChain(xCouple, cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "rx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyADC", false);
expectedCoupled = xCouple * cfg.rf.rx.element.mutualCoupling.matrix.';
assert(localMaxAbs(coupled.Waveform - expectedCoupled) < 1e-12, ...
    "Mutual coupling must apply the configured element-domain matrix to samples.");
assert(logical(coupled.Replay.MutualCouplingApplied) && ...
        string(coupled.Replay.MutualCouplingMatrixSize) == "rx:2x2", ...
    "RF replay must expose applied mutual-coupling evidence and matrix size.");

cfg = struct();
cfg.run.seed = 88;
cfg.rf.rx.phaseNoise.enable = true;
cfg.rf.phaseNoise.enable = true;
cfg.rf.phaseNoise.useCommBackend = false;
cfg.rf.phaseNoise.level_dBcHz = [-100 -100];
cfg.rf.phaseNoise.freqOffsetHz = [1 fs/2];
nPN = 8192;
phaseNoise = sixgr.rf.applyRFImpairmentChain(complex(ones(nPN, 1)), cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "rx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyADC", false);
expectedPhaseRMS = localExpectedFlatPhaseNoiseRMS(nPN, fs, -100);
assert(logical(phaseNoise.Replay.PhaseNoiseApplied), ...
    "Configured phase noise must apply through the ordered chain.");
assert(abs(double(phaseNoise.Replay.PhaseNoiseRMS_rad) - expectedPhaseRMS) < 1e-9, ...
    "Phase-noise RMS must close to the configured flat PSD integral.");
rowPN = phaseNoise.StageTrace(string(phaseNoise.StageTrace.StageName) == "rx_phase_noise", :);
assert(abs(double(rowPN.PowerDelta_dB)) < 1e-12, ...
    "Pure phase-noise rotation must conserve sample power.");

cfg = struct();
cfg.rf.tx.iqImbalance.enable = true;
cfg.rf.tx.iqImbalance.gainImbalance_dB = 0.8;
cfg.rf.tx.iqImbalance.phaseImbalance_deg = -4;
cfg.rf.tx.cfo_Hz = 80;
cfg.rf.tx.timingOffsetSamples = 0.25;
ordered = sixgr.rf.applyRFImpairmentChain(x, cfg, ...
    "SampleRateHz", fs, ...
    "Endpoint", "tx", ...
    "UseLegacyGlobalConfig", false, ...
    "StrictMutationRequired", true, ...
    "ApplyPA", false, ...
    "ApplyADC", false);
manual = localIQModel(x, 0.8, -4);
manual = localCFO(manual, 80, fs);
manual = sixgr.util.applyFractionalSampleDelay(manual, 0.25);
assert(localMaxAbs(ordered.Waveform - manual) < 1e-10, ...
    "Combined impairment output must equal declared stage composition.");
assert(string(ordered.Replay.RFStageOrder) == "tx_iq>tx_element_rf>tx_pa>tx_phase_noise>tx_cfo>tx_timing>tx_sample_clock_offset", ...
    "TX stage order must be immutable and explicit.");

cfg = struct();
cfg.phy.impairments.cfoHz = 125;
[linkY, linkReplay] = sixgr.link.applyWaveformImpairments(ones(64, 1), cfg, fs);
assert(localMaxAbs(linkY - expectedCFO) < 1e-12, ...
    "Link impairment bridge must use the ordered RX RF chain for legacy CFO.");
assert(logical(linkReplay.CFOApplied) && contains(string(linkReplay.RFStageOrder), "rx_lo_cfo"), ...
    "Link replay must expose ordered RF-chain CFO evidence.");

ok = true;
end

function y = localIQModel(x, gainImb_dB, phaseImb_deg)
[alpha, beta] = localIQAlphaBeta(gainImb_dB, phaseImb_deg);
y = alpha .* x + beta .* conj(x);
end

function [alpha, beta] = localIQAlphaBeta(gainImb_dB, phaseImb_deg)
g = 10.^(double(gainImb_dB) / 20);
phi = double(phaseImb_deg) * pi / 180;
alpha = 0.5 * (1 + g * exp(-1j * phi));
beta = 0.5 * (1 - g * exp(1j * phi));
end

function y = localCFO(x, cfoHz, fs)
n = (0:size(x, 1)-1).';
rot = exp(1j * 2 * pi * double(cfoHz) / double(fs) .* n);
y = x .* rot;
end

function y = localMemoryPolynomial(x, taps, orders, weights)
y = complex(zeros(size(x)));
for mi = 1:numel(taps)
    delay = mi - 1;
    xd = complex(zeros(size(x)));
    if delay == 0
        xd = x;
    elseif size(x, 1) > delay
        xd(1+delay:end, :) = x(1:end-delay, :);
    end
    for oi = 1:numel(orders)
        y = y + taps(mi) .* weights(oi) .* xd .* abs(xd).^(orders(oi) - 1);
    end
end
end

function y = localQuantize(x, bits, fullScale)
levels = 2^bits;
maxCode = levels / 2 - 1;
xr = min(max(real(double(x)), -fullScale), fullScale);
xi = min(max(imag(double(x)), -fullScale), fullScale);
y = complex(round((xr ./ fullScale) .* maxCode) ./ maxCode .* fullScale, ...
    round((xi ./ fullScale) .* maxCode) ./ maxCode .* fullScale);
end

function targetRMS = localExpectedFlatPhaseNoiseRMS(nSamples, fs, level_dBcHz)
freqAbs = (0:nSamples-1).' .* double(fs) ./ double(nSamples);
freqAbs(freqAbs > double(fs) / 2) = freqAbs(freqAbs > double(fs) / 2) - double(fs);
freqAbs = max(abs(freqAbs), 1);
posFreq = unique(freqAbs(freqAbs > 0 & freqAbs <= double(fs) / 2));
psd = repmat(10.^(double(level_dBcHz) / 10), size(posFreq));
targetRMS = sqrt(2 * trapz(posFreq, psd));
end

function e = localMaxAbs(x)
if isempty(x)
    e = 0;
else
    e = max(abs(double(x(:))));
end
end
