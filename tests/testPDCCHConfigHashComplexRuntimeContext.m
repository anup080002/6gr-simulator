function ok = testPDCCHConfigHashComplexRuntimeContext()
%TESTPDCCHCONFIGHASHCOMPLEXRUNTIMECONTEXT Runtime MIMO state is not hash input.

setup6GRSimToolkit("Verbose", false);

cfg = struct( ...
    "NCellID", 17, ...
    "NSizeGrid", 273, ...
    "CORESETId", 0, ...
    "SearchSpaceId", 1, ...
    "DCIContextDigest", "context-digest", ...
    "BaseConfig", struct("phy", struct("pdsch", struct( ...
        "precodingMatrix", [1 1i; -1i 1] / sqrt(2)))));

h1 = string(sixgr.phy.pdcch.hashPDCCHConfig(cfg));
cfg.BaseConfig.phy.pdsch.precodingMatrix = [1 -1i; 1i 1] / sqrt(2);
h2 = string(sixgr.phy.pdcch.hashPDCCHConfig(cfg));
assert(h1 == h2, ...
    "PDCCH assignment hash must exclude unrelated complex runtime PHY state.");

cfg.CORESETId = 1;
h3 = string(sixgr.phy.pdcch.hashPDCCHConfig(cfg));
assert(h3 ~= h1, ...
    "PDCCH assignment hash must change when canonical CORESET state changes.");

ok = true;
end
