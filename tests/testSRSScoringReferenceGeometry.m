function ok=testSRSScoringReferenceGeometry()
% Actual prepared/received SRS component, not full shared-H4 qualification.
% A declared four-branch connector and independent AWGN produce samples.
% The noiseless reference is scoring-only, never practical receiver input.
setup6GRSimToolkit('Verbose',false);
folder=fullfile(pwd,'results','diagnostics','srs_scoring_reference_geometry', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(folder);
source=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_tdd_5mhz_four_port_shared_awgn_12db.yaml');
base=sixgr.lls6g.buildInternalConfig(source,folder);
base=sixgr.phy.grid.applyRuntimeCarrierTimeline(base,5,1);
base.phy.srs.runtimeChannelEstimator='nr_channel_estimate';
prior=rng; cleanup=onCleanup(@()rng(prior)); %#ok<NASGU>
rows=table();
for comb=[2 4]
    cfg=base;
    cfg.phy.srs.KTC=comb;
    cfg.lls6g.reference_signals.srs.comb_number=comb;
    args={'SlotIndex',5,'TrialIndex',1,'SNR_dB',40,'TimingAdvanceSamples',0};
    pending=sixgr.link.runSRSChannelEstimation(cfg,args{:},'PrepareOnly',true);
    p=pending.PreparedTransmission;
    assert(p.Tx.SRS.NumSRSPorts==4 && p.Tx.SRS.KTC==comb && ...
        p.NumPhysicalTransmitAntennas==4 && p.NumReceiveAntennas==4);
    array=sixgr.rf.AntennaArrayFactory.build(p.ReceiverConfig,'ue', ...
        'signal','srs','numPorts',size(p.Tx.Waveform,2));
    transmitted=p.Tx.Waveform*array.PortToElementMatrix.';
    connector=diag([1,0.8*exp(0.3i),0.7*exp(-0.4i),0.9]);
    desired=transmitted*connector;
    energy=sixgr.phy.waveform.measureReceivedOccupiedREEnergy( ...
        p.Tx.Carrier,desired,p.Tx.SRSIndices,'SignalFamily','SRS');
    rng(148300+comb,'twister');
    [observed,noise]=sixgr.phy.waveform.addOccupiedREAWGN( ...
        desired,p.Tx.Carrier,40,'SignalEnergyPerOccupiedRE',energy);
    replay=struct('SampleNoiseVariance',NaN, ...
        'SampleNoiseVarianceDomain',"unavailable_requires_received_reference_estimation", ...
        'NoiseOperatingMode',"standalone_awgn_snr_argument", ...
        'ConfiguredSNR_dB',40,'AppliedAWGNSNR_dB',40, ...
        'ApproximationMode',"none");
    input=struct('Prepared',p,'Observation',buffer(p,observed), ...
        'PhysicalMeasurementObservation',buffer(p,observed), ...
        'TransmitterObservation',buffer(p,transmitted), ...
        'DesiredReferenceObservation',buffer(p,desired), ...
        'Replay',replay,'ChannelState',struct('Profile',"AWGN", ...
        'Source',"declared_four_branch_component_connector"));
    before=rng;
    [out,capture]=sixgr.link.runSRSChannelEstimation(cfg,args{:},'ReceivedContext',input);
    assert(isequal(before,rng),'Scoring completion must not re-execute random channel/noise.');
    timing=capture.Rx.Timing;
    aligned=desired(timing.AppliedTimingCorrectionSamples+(1:timing.DemodulatedSampleCount),:);
    referenceGrid=sixgr.phy.waveform.ofdmDemodulate(p.Tx.Carrier,aligned);
    % Native independent call with the configured four-port CDM geometry.
    expectedReference=nrChannelEstimate(p.Tx.Carrier,referenceGrid, ...
        p.Tx.SRSIndices,p.Tx.SRSSymbols,'CDMLengths',[4 1]);
    expected=sixgr.phy.srs.pilotChannelNMSE( ...
        capture.Rx.Hest,expectedReference,p.Tx.SRSIndices);
    actualCDM=out.ChannelNMSEReferenceEvidence.ScoringEstimatorInfo.CDMLengths;
    row=table(comb,actualCDM(1),actualCDM(2),out.RawChannelNMSE_dB,expected.dB, ...
        string(out.NoiseVarSource),string(out.NMSEReferenceSource), ...
        'VariableNames',{'Comb','ScoringFDCDMLength','ScoringTDCDMLength', ...
        'ActualRawNMSE_dB','IndependentRawNMSE_dB','ReceiverNoiseSource','ReferenceSource'});
    rows=[rows;row]; %#ok<AGROW>
    writetable(rows,fullfile(folder,'reference_geometry.csv'));
    save(fullfile(folder,sprintf('comb%d.mat',comb)), ...
        'cfg','input','out','capture','noise','expected','actualCDM');
    assert(isequal(actualCDM,[4 1]),'test:SRSScoringCDMGeometry', ...
        'Four-port scoring must use the configured port set, not generic two-port inference. Evidence: %s',folder);
    assert(abs(out.RawChannelNMSEScoring.Linear-expected.Linear)<1e-12, ...
        'test:SRSScoringNativeReferenceMismatch','Scoring must match the independent native reference.');
    assert(~out.ChannelNMSEReferenceEvidence.ReceiverEstimatorInput && ...
        out.ChannelNMSEReferenceEvidence.AdditionalChannelExecutions==0 && ...
        ~out.ChannelNMSEReferenceEvidence.ComparisonGainFitted);
    assert(~capture.RxInfo.ChannelEstimation.PrimaryEstimatorFallbackUsed && ...
        isequal(capture.RxInfo.ChannelEstimation.CDMLengths,[4 1]) && ...
        string(out.NoiseVarSource)=="received_srs_inband_null_re_disturbance");
    changed=input;
    changed.DesiredReferenceObservation=buffer(p,2*desired);
    [poisoned,poisonedCapture]=sixgr.link.runSRSChannelEstimation( ...
        cfg,args{:},'ReceivedContext',changed);
    assert(isequaln(capture.Rx.Hest,poisonedCapture.Rx.Hest) && ...
        isequaln(capture.Rx.NoiseVar,poisonedCapture.Rx.NoiseVar) && ...
        isequaln(out.RIEstimate,poisoned.RIEstimate) && ...
        isequaln(out.TPMIEstimate,poisoned.TPMIEstimate) && isequaln(out.CQI,poisoned.CQI), ...
        'test:SRSScoringReferenceLeak','Scoring-only IQ must not affect noise or spatial feedback.');
    assert(abs(poisoned.RawChannelNMSEScoring.Linear-out.RawChannelNMSEScoring.Linear)>0.1, ...
        'Scoring must still expose changed reference gain rather than fit it away.');
end
fprintf('SRS_SCORING_REFERENCE_GEOMETRY_PASS received_cases=%d evidence=%s\n',height(rows),folder);
ok=true;
end

function b=buffer(p,samples)
b=sixgr.phy.waveform.WaveformObservationBuffer( ...
    p.StartSample,p.StartSample+size(samples,1),p.SampleRateHz,size(samples,2));
b.append(sixgr.phy.waveform.WaveformChunk(samples,p.StartSample),p.SampleRateHz);
end
