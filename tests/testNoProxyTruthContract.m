function ok = testNoProxyTruthContract(nUE)
%TESTNOPROXYTRUTHCONTRACT No-proxy truth requests must fail closed when unsupported.

setup6GRSimToolkit("Verbose", false);
if nargin<1, nUE=1; end
validateattributes(nUE,{'numeric'},{'scalar','integer','>=',1,'<=',2});

cfgPhy = sixgr.config.defaultConfig();
cfgPhy.run.noProxyTruthContract = true;
threwAbstract = false;
try
    sixgr.system.PhyFactory.create(cfgPhy, struct( ...
        "PHYBackend", "abstract", ...
        "NoProxyTruthContract", true)); %#ok<NASGU>
catch ME
    threwAbstract = strcmp(ME.identifier, "sixgr:system:ProxyBackendRemoved");
    assert(contains(string(ME.message), "System PHY backend"), ...
        "No-proxy PhyFactory guard should explain the waveform-system requirement.");
end
assert(threwAbstract, "No-proxy truth contract must reject AbstractPHY system backends.");

tmp = fullfile(pwd,'results','sls','e2e_no_proxy_contract', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(tmp);
fprintf('E2E_NO_PROXY_EVIDENCE_ROOT=%s\n',tmp);

cfgLink = sixgr.config.defaultConfig();
cfgLink.run.noProxyTruthContract = true;
cfgLink.channel.model = "TDL-C";
cfgLink.channel.awgnOnly = false;
cfgLink.channel.dopplerHz = 70;
cfgLink.channel.fading.enable = true;
cfgLink.channel.fading.model = "TDL";
cfgLink.channel.fading.profile = "TDL-C";
cfgLink.channel.fading.maxDoppler_Hz = 70;
threwFastLink = false;
try
    sixgr_run_3gpp_full_campaign(cfgLink, ...
        "ResultsRoot", tmp, ...
        "OnlyE2E", false, ...
        "RunLinkCampaign", true, ...
        "RunDetailedLinkDiagnostics", false, ...
        "RunSystemMMTCProbe", false, ...
        "RunAuxiliaryProbes", false, ...
        "RunE2EStackProbe", false, ...
        "SystemDuration_s", 0.001, ...
        "UseFastLinkModel", true, ...
        "UseMexAcceleration", false, ...
        "UseParallelAcceleration", false, ...
        "AutoStartParallelPool", false, ...
        "NoProxyTruthContract", true, ...
        "Verbose", false); %#ok<NASGU>
catch ME
    threwFastLink = any(strcmp(ME.identifier, ["sixgr:campaign:ProxyModeRemoved","sixgr:truth:NoProxyContractViolation","sixgr:link:NoProxyFastLinkForbidden"]));
end
assert(threwFastLink, "No-proxy truth contract must reject fast-link proxy execution.");

% Strict E2E truth executes the actual four-step RA and typed control/data
% chain.  Start from a fully resolved scenario so carrier/frame, PRACH,
% CORESET/search-space and PDCCH allocations all share one YAML authority.
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile(pwd, ...
    "simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring_tdd.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scenario, ...
    fullfile(tmp, "no_proxy_truth_runtime"));
cfg.run.strictMode = true;
cfg.channel.model = "TDL-C";
cfg.channel.tdlProfile = "TDL-C";
cfg.channel.cdlProfile = "";
cfg.channel.delayProfile = "TDL-C";
cfg.channel.awgnOnly = false;
cfg.channel.dopplerHz = 70;
cfg.channel.fading.enable = true;
cfg.channel.fading.model = "TDL";
cfg.channel.fading.profile = "TDL-C";
cfg.channel.fading.maxDoppler_Hz = 70;
cfg.traffic.model = "traceReplay";
% Include data slots after physical broadcast plus RA/RRC completion. The
% earlier 20-slot fixture could pass with every offered row attach-gated.
nSlots=40+30*(nUE-1);
cfg.traffic.trace.offeredBitsDL = 200 * ones(nSlots, nUE);
cfg.traffic.trace.offeredBitsUL = zeros(nSlots, nUE);
cfg.traffic.trace.transport = "UDP";
cfg.traffic.trace.flowDirection = "DL";
cfg.scenario.ue.nUE = nUE;
cfg.scenario.nUE = nUE;

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmp, ...
    "OnlyE2E", true, ...
    "RunLinkCampaign", false, ...
    "RunDetailedLinkDiagnostics", false, ...
    "RunSystemMMTCProbe", false, ...
    "RunAuxiliaryProbes", false, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", nSlots*sixgr.time.slotDurationSec(cfg), ...
    "E2EMaxSlots", nSlots, ...
    "E2EUECount", nUE, ...
    "E2ETrafficModel", "traceReplay", ...
    "E2EAirModel", "truth", ...
    "E2EStrictValidation", true, ...
    "E2ETruthFastAWGNPath", false, ...
    "E2ETruthCompactPHYIO", true, ...
    "E2ETruthAdaptiveLDPC", true, ...
    "E2ETruthLDPCMaxIterations", 0, ...
    "E2ETruthUseGPU", false, ...
    "E2ETruthMaxSlots", nSlots, ...
    "LinkSNR_dB", 30, ...
    "CalibrateSystemBLERFromLink", false, ...
    "UseFastLinkModel", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "GenerateCampaignPlots", false, ...
    "VerifyArtifacts", false, ...
    "NoProxyTruthContract", true, ...
    "Verbose", false);

assert(rep.Ok, "No-proxy truth contract should now allow system-coupled truth E2E.");
assert(logical(sixgr.util.structGet(rep.E2E, "SystemCoupled", false)), ...
    "No-proxy truth E2E must be system-coupled.");
assert(string(sixgr.util.structGet(rep.E2E, "CouplingMode", "")) == "system_waveform_grant_trace", ...
    "No-proxy truth E2E must use the system waveform grant trace coupling mode.");
assert(~isempty(rep.E2E.SchedulerTraceTable), ...
    'No-proxy E2E acceptance requires actual post-attach waveform data grants.');
assert(ismember('RNTI',rep.E2E.SchedulerTraceTable.Properties.VariableNames), ...
    'Packet replay must export protocol identity separately from UE array index.');
assert(all(isfinite(rep.E2E.SchedulerTraceTable.RNTI)), ...
    'Executed packet grants require real protocol identities.');
bindings=rep.E2E.ReceivedAccessBindings;
assert(height(bindings)==nUE && numel(unique(bindings.RNTI))==nUE && ...
    all(bindings.IdentitySource=="decoded_msg4_payload_after_contention_match"));
assert(numel(rep.E2E.ReceivedULAccess)==nUE, ...
    'The received SIB1/RAR timing state must survive the system handoff.');
savedAccess=load(fullfile(rep.RunFolder,'packet_flow','mat','e2e_received_access_results.mat'));
timingCSV=readtable(fullfile(rep.RunFolder,'packet_flow','csv','e2e_received_ul_timing.csv'), ...
    'TextType','string','VariableNamingRule','preserve');
assert(height(timingCSV)==nUE && all(timingCSV.RNTI==bindings.RNTI) && ...
    ~any(timingCSV.PhysicalSRSReceived) && ~any(timingCSV.WaveformTimingApplied));
assert(ismember('TimeAlignmentExpirySampleExclusive',timingCSV.Properties.VariableNames), ...
    'An infinite received time-alignment timer must not remove the expiry column.');
for ue=1:nUE
    access=rep.E2E.ReceivedULAccess{ue};
    assert(isequaln(timingCSV.TimeAlignmentExpirySampleExclusive(ue), ...
        access.ConnectedULTiming.TimeAlignmentExpirySampleExclusive), ...
        'CSV timing expiry must match the retained received timing state.');
    receipt=savedAccess.Receipts{ue};
    row=receipt.Result.RuntimeStageRows;
    row=row(string(row.StageName)=="Msg2",:);
    assert(access.UEIndex==ue && ...
        access.ConnectedULTiming.TimingAdvanceAvailableAtSample==row.ObservationEndSampleExclusive && ...
        ~access.PhysicalSRSReceived && ~access.WaveformTimingApplied, ...
        'Resolved timing is not executed connected UL or a received SRS measurement.');
    changed=receipt;
    changed.Result.DecodedRAR.TimingAdvanceCommand=3846;
    changed.DecodedSIB1.SIB1RxTree.message.c1.systemInformationBlockType1. ...
        servingCellConfigCommon.uplinkConfigCommon.timeAlignmentTimerCommon="ms500";
    restored=sixgr.system.resolveReceivedAccessULTiming(cfg,changed);
    assert(isequaln(restored,access),'Received bytes must own TA/timer, not mutable labels.');
    changed=receipt; changed.Result.Msg2PDSCHCrcPass=false;
    try
        sixgr.system.resolveReceivedAccessULTiming(cfg,changed);
        error('test:MissingRARRejection','Unaccepted RAR unexpectedly installed timing.');
    catch ex
        assert(strcmp(ex.identifier,'sixgr:system:UnacceptedAccessRAR'),ex.message);
    end
    changed=receipt; changed.DecodedSIB1=rmfield(changed.DecodedSIB1,'ReceivedDLTimingReference');
    try
        sixgr.system.resolveReceivedAccessULTiming(cfg,changed);
        error('test:MissingClockRejection','Missing DL clock unexpectedly installed timing.');
    catch ex
        assert(strcmp(ex.identifier,'sixgr:system:MissingAccessDLClock'),ex.message);
    end
end
grants=rep.E2E.SchedulerTraceTable;
assert(numel(unique(grants.UE))==nUE,'Each physically attached UE must execute a data grant.');
for ue=1:nUE
    selected=grants(grants.UE==ue,:);
    assert(all(selected.RNTI==bindings.RNTI(ue)) && ...
        all(selected.Slot>bindings.BlockedSlotCount(ue)), ...
        'Each grant must use that UE received C-RNTI after its actual receive-completion gate.');
end
attach=readtable(fullfile(rep.RunFolder,'packet_flow','csv','e2e_attach_trace.csv'), ...
    'TextType','string','VariableNamingRule','preserve');
assert(all(diff(attach.Slot)>=0),'Physical attach exports must not wrap at frame boundaries.');
assert(attach.Slot(end)==attach.Slot(end-1), ...
    'ATTACH_CONNECTED must agree with the actual final RRC event clock.');
fprintf('E2E_NO_PROXY_RUN_FOLDER=%s GRANT_ROWS=%d\n', ...
    char(string(rep.RunFolder)),height(rep.E2E.SchedulerTraceTable));

ok = true;
end
