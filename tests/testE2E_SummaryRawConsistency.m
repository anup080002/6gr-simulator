function ok = testE2E_SummaryRawConsistency()
%TESTE2E_SUMMARYRAWCONSISTENCY Ensure packet summary matches raw truth trace.

setup6GRSimToolkit("Verbose", false);
defaults = sixgr.config.defaultConfig();
tmp = fullfile(pwd,'results','sls','summary_raw_consistency', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(tmp);
fprintf('SUMMARY_RAW_CONSISTENCY_EVIDENCE_ROOT=%s\n',tmp);
[cfg,nSlots] = e2eReceivedAccessConfig(tmp,2);
% Access configuration must not silently change this packet-accounting
% fixture into a codebook/SRS-selection test. Preserve its original UL
% transmission scheme and layer count; sounding guards remain unchanged.
cfg.phy.pusch.transmissionScheme = defaults.phy.pusch.transmissionScheme;
cfg.phy.pusch.TransmissionScheme = defaults.phy.pusch.transmissionScheme;
cfg.phy.pusch.nLayers = defaults.phy.pusch.nLayers;
cfg.phy.pusch.numLayers = defaults.phy.pusch.nLayers;
assert(strcmpi(cfg.phy.pusch.transmissionScheme,'nonCodebook') && ...
    cfg.phy.pusch.nLayers==1, ...
    'Review this fixture if the original default UL transmission domain changes.');
% Retain the original bidirectional mMTC traffic configuration, not the
% publication helper's DL-only trace. Declare its formerly implicit flow
% explicitly so strict producer ownership does not need a fallback.
cfg.traffic = defaults.traffic;
cfg.traffic.model = 'mmtc';
cfg.traffic.flows = struct('name','mmtc','service_profile','mmtc', ...
    'direction',cfg.traffic.flowDirection,'protocol',cfg.traffic.transport, ...
    'qfi',cfg.traffic.qos.default5QI,'fiveQi',cfg.traffic.qos.default5QI, ...
    'packetDelayBudget_ms',cfg.traffic.packetDelayBudget_ms, ...
    'packetSize_bytes',cfg.traffic.packetSize_bytes, ...
    'packetInterval_ms',cfg.traffic.packetInterval_ms, ...
    'rate_Mbps',cfg.traffic.targetRate_Mbps,'jitterPct',cfg.traffic.jitterPct, ...
    'weight',1,'burstiness','medium');
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.run.seed = 29;
% Preserve evidence on success and failure; do not delete receiver traces.
save(fullfile(tmp,'test_configuration.mat'),'cfg','nSlots');

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmp, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", nSlots*sixgr.time.slotDurationSec(cfg), ...
    "E2EMaxSlots", nSlots, ...
    "E2EUECount", 2, ...
    "E2ETrafficModel", "mmtc", ...
    "E2EAirModel", "truth", ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", false, ...
    "GenerateCampaignPlots", false, ...
    "E2EStrictValidation", false, ...
    "E2ETruthMaxSlots", nSlots);

assert(height(rep.E2E.ReceivedAccessBindings)==2, ...
    'Summary/raw consistency requires actual received access for both UEs.');
grants = rep.E2E.SchedulerTraceTable;
assert(~isempty(grants) && all(ismember(["DL","UL"], ...
    upper(string(grants.Direction)))), ...
    'Bidirectional accounting coverage requires executed DL and UL grants.');

raw = rep.E2E.PacketTraceTable;
summary = rep.E2E.PacketIntegrityTable;
dirCol = upper(string(raw.Direction));
dropCause = string(raw.DropCause);
isDelivered = (strlength(dropCause) == 0);
assert(all(ismember(["DL","UL"],dirCol)), ...
    'The original bidirectional packet populations must both be exercised.');

for d = ["DL","UL","ALL"]
    row = summary(upper(string(summary.Direction)) == d, :);
    assert(height(row) == 1, "Missing packet-integrity row for %s.", d);
    if d == "ALL"
        idx = true(height(raw), 1);
    else
        idx = (dirCol == d);
    end
    idxDel = idx & isDelivered;
    lat = double(raw.Latency_ms(idxDel));
    lat = lat(isfinite(lat));

    expectedGen = sum(idx);
    expectedDel = sum(idxDel);
    expectedUnd = sum(idx & ~isDelivered);
    expectedMiss = sum(idx & logical(raw.DeadlineMiss));
    expectedDup = sum(idx & logical(raw.DuplicateFlag));
    expectedReord = sum(idx & logical(raw.ReorderFlag));
    expectedMissRate = expectedMiss / max(expectedGen, 1);

    assert(double(row.GeneratedPackets) == expectedGen, "Generated packet mismatch for %s.", d);
    assert(double(row.DeliveredPackets) == expectedDel, "Delivered packet mismatch for %s.", d);
    assert(double(row.UndeliveredPackets) == expectedUnd, "Undelivered packet mismatch for %s.", d);
    assert(double(row.DeadlineMissPackets) == expectedMiss, "Deadline miss mismatch for %s.", d);
    assert(double(row.DuplicatePackets) == expectedDup, "Duplicate packet mismatch for %s.", d);
    assert(double(row.OutOfOrderPackets) == expectedReord, "Reorder packet mismatch for %s.", d);
    assert(abs(double(row.DeadlineMissRate) - expectedMissRate) <= 1e-12, ...
        "Deadline miss rate mismatch for %s.", d);

    if isempty(lat)
        assert(isnan(double(row.MeanLatency_ms)), "Mean latency should be NaN when no packets are delivered for %s.", d);
        assert(isnan(double(row.P95Latency_ms)), "P95 latency should be NaN when no packets are delivered for %s.", d);
    else
        assert(abs(double(row.MeanLatency_ms) - mean(lat)) <= 1e-9, "Mean latency mismatch for %s.", d);
        assert(abs(double(row.P95Latency_ms) - prctile(lat, 95)) <= 1e-9, "P95 latency mismatch for %s.", d);
    end
end

[resultIntegrityTable, integritySummary] = sixgr.report.checkResultIntegrity(struct( ...
    "SummaryTable", rep.E2E.SummaryTable, ...
    "PacketIntegrityTable", rep.E2E.PacketIntegrityTable, ...
    "FlowSummaryTable", rep.E2E.FlowSummaryTable, ...
    "BearerSummaryTable", rep.E2E.BearerSummaryTable, ...
    "PacketTraceTable", rep.E2E.PacketTraceTable, ...
    "CheckTable", rep.E2E.CheckTable), ...
    "StrictMode", true, ...
    "ContextLabel", "test_e2e_summary_raw_consistency");
assert(integritySummary.Ok && all(logical(resultIntegrityTable.Pass)), ...
    "Strict summary/raw integrity validation must pass on coherent truth traces.");
assert(double(rep.E2E.SummaryTable.ResultIntegrityFailureCount(1)) == 0, ...
    "Truth E2E summary must report zero result-integrity failures.");
assert(abs(double(rep.E2E.SummaryTable.PacketAccountingPassRate_pct(1)) - ...
    100 * mean(double(rep.E2E.PacketIntegrityTable.AccountingIntegrityPass))) <= 1e-9, ...
    "Packet-accounting pass rate must match packet-integrity accounting rows.");

ok = true;
end
