    'AvailableAtSample',sixgr.phy.frame.slotStartSample(tx.Carrier,a.ControlAbsoluteSlot+1,fs));
[~,pc,~,~,owner]=owner.resolvePUSCH(allocation.Config,a,tx,obs);
assert(pc.UpdatedF_dB==1 && pc.StateUpdateCount==1);
end

function validateRetainedEnergy(folder)
% An independent RF-input accumulator proves the replacement reached the
% physical runtime, not only the prepared-waveform labels or receipt hashes.
actual=load(fullfile(folder,'received.mat'),'p','out','scope');
record=load(fullfile(folder,'rf_execution.mat'),'ledger');
p=actual.p; e=record.ledger; rows=e.Intervals;
assert(e.CompleteFromSampleZero && e.ChainPowerCompleteFromOrigin && ...
    ~actual.scope.ScenarioAccepted && ~actual.scope.StatisticallyQualified);
array=sixgr.rf.AntennaArrayFactory.build(p.ReceiverConfig,'ue', ...
    'signal','srs','numPorts',size(p.Tx.Waveform,2));
mapped=p.Tx.Waveform*cast(array.PortToElementMatrix.','like',p.Tx.Waveform);
expected=sum(abs(double(mapped)).^2,'all');
selected=rows.Role=="TX" & rows.EndpointID=="ue_1";
measured=sum(rows.InputSquaredMagnitudeSum(selected));
assert(expected>0 && abs(measured-expected)<1e-10*expected, ...
    'test:SharedSRSPowerNotEmitted','Actual RF-input energy must match the rebound physical SRS samples.');
assert(p.Metadata.PowerEvidence.Adjustment_dB==1 && p.Metadata.PowerEvidence.BoundAtEmission);
assert(actual.out.Ok && actual.out.ChannelNMSEScoring.Available);
fprintf('SHARED_SRS_POWER_RF_INPUT_CLOSURE expected=%0.15g measured=%0.15g relative_error=%g\n', ...
    expected,measured,abs(expected-measured)/expected);
end
