function [row,originalFields]=receiverPublicationRow(cfg,out,scope)
% The test is a row producer too: never let missing fields become schema
% defaults which contradict the actual receiver. No new qualification is
% calculated here; even Status uses the collector's original Ok/Skipped map.
power=sixgr.link.srsPowerControlEvidence();
antenna=sixgr.phy.srs.measureSRSAntennaPower();
reference=sixgr.truth.scoreSharedSRSAntennaPower();
channel=sixgr.link.srsReferenceEvidence();
waveform=sixgr.link.receivedWaveformEvidence();
direct=[string(fieldnames(power)); ...
    setdiff(string(fieldnames(antenna)),"SRSRSRPPerReceiveAntenna_dBm"); ...
    string(fieldnames(reference));string(fieldnames(channel));string(fieldnames(waveform)); ...
    ["Ok";"Skipped";"StrictOk";"StrictReceiverEvidenceOk";"SRSRuntimeEvidenceUsable"; ...
    "ChannelNMSEThreshold_dB";"NMSE_dB";"RawChannelNMSE_dB";"NMSEReferenceSource"; ...
    "ChannelNMSEQualificationMode";"TrueChannelOracleAvailable";"TrueChannelNMSE_dB"; ...
    "DetectionAttempted";"DetectionSuccess";"DetectionUsable"; ...
    "ResourceExtractionAttempted";"ResourceExtractionAvailable"; ...
    "ChannelEstimateAttempted";"ChannelEstimateAvailable";"SRSChannelEstimateAvailable"; ...
    "ChannelEstimateSource";"MeasurementAttempted";"MeasurementUsable";"FailureReason"; ...
    "RankEstimate";"RIEstimate";"TPMIEstimate";"EstimatedRI";"EstimatedTPMI"; ...
    "RISource";"TPMISource";"TPMICandidateCount";"TPMIMutualInformation"; ...
    "SINR_dB";"SINRSource";"SINRValueStatus";"SINRMeasurementDomain";"ConfiguredSNR_dB"]];
direct=unique(direct,'stable');
assert(all(isfield(out,cellstr(direct))) && ...
    isfield(out,'SRSRSRPPerReceiveAntenna_dBm') && ...
    all(isfield(scope,{'ScenarioAccepted','StatisticallyQualified'})), ...
    'test:MissingOriginalSRSReceiverFields','Republish only the original complete receiver result.');
fields=struct();
for name=direct.'
    value=out.(name);
    if ischar(value), value=string(value); end
    fields.(name)=value;
end
fields.ReceiverOk=out.Ok;
fields.ReceiverUsable=out.StrictReceiverEvidenceOk;
fields.DecodeUsable=out.StrictOk;
fields.RankIndicator=out.RIEstimate;
fields.PMI=out.TPMIEstimate;
fields.Status="FAIL";
if out.Ok && ~out.Skipped, fields.Status="PASS";
elseif out.Skipped, fields.Status="NA"; end
fields.PublicationStatusSource="original_receiver_Ok_Skipped_collector_mapping";
fields.SRSRSRPPerReceiveAntenna_dBm=string(jsonencode(out.SRSRSRPPerReceiveAntenna_dBm));
fields.ScenarioAccepted=scope.ScenarioAccepted;
fields.StatisticallyQualified=scope.StatisticallyQualified;
fields=sixgr.truth.bindReferenceSignalSINREvidence(fields,out,"SRS");
originalFields=struct2table(fields,'AsArray',true);
row=sixgr.truth.SharedDataCompletionRuntime.ensureLinkTrialTable( ...
    originalFields,"UL",out.ConfiguredSNR_dB,cfg);
assertReceiverFields(row,originalFields);
end

function writeReceiverPublication(folder,cfg,row,originalFields)
path=fullfile(folder,'srs_power_result.csv');
assert(~isfile(path),'test:SRSOriginalPublicationOverwrite', ...
    'A publication must use a new file; never replace retained evidence.');
sixgr.truth.writeOptionalRuntimeFeatureTable(cfg,"srs",path,row,'PreserveSchema',true);
% Explicit wire types preserve false, NaN, literal NA and empty text without
% inferring a schema from this one row. No values are supplied by the reader.
options=detectImportOptions(path,'Delimiter',',','VariableNamingRule','preserve');
options.VariableNamesLine=1; options.DataLines=[2 Inf];
options.ImportErrorRule='error';
for name=string(originalFields.Properties.VariableNames)
    value=originalFields.(name);
    assert(isscalar(value) && (isnumeric(value)||islogical(value)||isstring(value)), ...
        'test:SRSReceiverPublicationSchema','Receiver projection fields must be scalar values.');
    options=setvartype(options,char(name),class(value));
    if isstring(value)
        options=setvaropts(options,char(name),'WhitespaceRule','preserve', ...
            'EmptyFieldRule','auto','TreatAsMissing',{});
    end
end
exported=readtable(path,options);
assertReceiverFields(exported,originalFields);
assert(isequaln(exported.StrictOk,originalFields.StrictOk) && ...
    isequaln(exported.ChannelNMSEThreshold_dB,originalFields.ChannelNMSEThreshold_dB) && ...
    isequaln(exported.MeasuredTrialSINR_dB,originalFields.SINR_dB), ...
    'test:SRSReceiverPublicationMismatch','Publication must retain actual qualification and SINR.');
end

function assertReceiverFields(row,originalFields)
assert(height(row)==1,'test:SRSReceiverPublicationMismatch','One actual receiver result is required.');
for name=string(originalFields.Properties.VariableNames)
    assert(ismember(name,string(row.Properties.VariableNames)) && ...
        isequaln(row.(name),originalFields.(name)), ...
        'test:SRSReceiverPublicationMismatch','Original receiver field %s changed in publication.',name);
end
end

function publicationFolder=republishReceiverRow(retainedFolder)
% Load scalar receiver output/configuration only, not saved IQ or live owners.
% Original artifacts remain immutable; this is a new diagnostic projection,
% not another physical trial and not a repair of the historical CSV in place.
originalFolder=char(java.io.File(char(retainedFolder)).getCanonicalPath());
paths=string(fullfile(originalFolder, ...
    {'received.mat','configuration.mat','srs_power_result.csv'}));
assert(isfolder(originalFolder) && all(isfile(paths)), ...
    'test:MissingOriginalSRSArtifacts','Retain the completed source MAT/configuration/CSV.');
hash=@sixgr.phy.waveform.WaveformHash.file;
before=strings(size(paths));
for k=1:numel(paths), before(k)=hash(paths(k)); end
randomState=rng;
saved=load(paths(1),'out','scope'); installed=load(paths(2),'ul');
[row,originalFields]=receiverPublicationRow(installed.ul,saved.out,saved.scope);
[parent,name]=fileparts(originalFolder);
publicationFolder=string(fullfile(parent,[name '_receiver_publication_' ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS'))]));
assert(~isfolder(publicationFolder) && ~isfile(publicationFolder), ...
    'test:SRSOriginalPublicationOverwrite','Choose a new sibling diagnostic folder.');
mkdir(publicationFolder);
metadata=struct('PublicationMode',"original_saved_receiver_projection_no_PHY_reexecution", ...
    'PublicationOnlyReplay',true,'NoNewPHY',true, ...
    'SourceReceivedMATPath',paths(1),'SourceReceivedMATSHA256',before(1), ...
    'SourceConfigurationMATPath',paths(2),'SourceConfigurationMATSHA256',before(2), ...
    'OriginalCSVPath',paths(3),'OriginalCSVSHA256',before(3));
receipt=metadata;
receipt.ContractVersion="sixgr.test.SRSReceiverPublicationSource/v1";
receipt.SourceAuthority="original_saved_receiver_output_not_historical_CSV_defaults";
for name=["ReceiverObservationSHA256","ReceiverObservationHashPlane", ...
        "ReceiverObservationHashSerialization","ObservationStartSample", ...
        "ObservationEndSampleExclusive","ObservationSampleRateHz", ...
        "SRSAbsolutePowerEvidenceSHA256","SRSRSRPReferenceEvidenceSHA256", ...
        "ChannelNMSEReferenceEvidenceSHA256"]
    receipt.(name)=saved.out.(name);
end
metadata.SourceReceipt=string(jsonencode(receipt));
metadata.SourceReceiptSHA256=string(sixgr.rrc.asn1.asn1SHA256Hex( ...
    unicode2native(char(metadata.SourceReceipt),'UTF-8')));
for name=string(fieldnames(metadata)).'
    row.(name)=metadata.(name);
    originalFields.(name)=metadata.(name);
end
writeReceiverPublication(publicationFolder,installed.ul,row,originalFields);
after=strings(size(paths));
for k=1:numel(paths), after(k)=hash(paths(k)); end
assert(isequal(before,after) && isequal(rng,randomState), ...
    'test:SRSOriginalArtifactsChanged','Read-only replay must preserve originals and random state.');
audit=table(paths(:),before(:),after(:),'VariableNames', ...
    {'OriginalArtifact','SHA256Before','SHA256After'});
sixgr.util.csvWriteTable(fullfile(publicationFolder,'source_integrity.csv'),audit,'PreserveSchema',true);
fprintf(['SHARED_SRS_RECEIVER_REPUBLICATION_PASS original=%s diagnostic=%s ' ...
    'strict_ok=%d rank=%g sinr_db=%.17g new_PHY=0 originals_unchanged=1\n'], ...
    originalFolder,publicationFolder,saved.out.StrictOk,saved.out.EstimatedRI,saved.out.SINR_dB);
end

function assertReferenceRejects(out,item,input,owner,replacement)
original=jsondecode(out.SRSAbsolutePowerEvidenceJSON);
fields=["ObservationStartSample","ObservationEndSampleExclusive","ContractVersion", ...
    "Source","AlignedWaveformSHA256","GridSHA256","ResourceSupportSubcarrier0Symbol0"];
for name=fields
    changed=original;
    if any(name==["ObservationStartSample","ObservationEndSampleExclusive"])
        changed.FFTSupport.(name)=changed.FFTSupport.(name)+1;
    elseif name=="ResourceSupportSubcarrier0Symbol0"
        changed.FFTSupport.(name)(1)=changed.FFTSupport.(name)(1)+1;
    else
        changed.FFTSupport.(name)="not_the_original_"+string(changed.FFTSupport.(name));
    end
    bad=out; bad.SRSAbsolutePowerEvidenceJSON=string(jsonencode(changed));
    bad.SRSAbsolutePowerEvidenceSHA256=string(sixgr.rrc.asn1.asn1SHA256Hex( ...
        unicode2native(char(bad.SRSAbsolutePowerEvidenceJSON),'UTF-8')));
    denied=sixgr.truth.scoreSharedSRSAntennaPower(bad,item,input,owner);
    assert(~denied.SRSRSRPReferenceAvailable && isnan(denied.SRSRSRPEstimationError_dB) && ...
        denied.SRSRSRPReferenceErrorIdentifier=="sixgr:truth:SRSRSRPReferenceIdentity");
end
badItem=item;
badItem.Context.SRSComponentBinding.ComponentSHA256=replacement.OriginalSampleSHA256;
denied=sixgr.truth.scoreSharedSRSAntennaPower(out,badItem,input,owner);
assert(~denied.SRSRSRPReferenceAvailable && ...
    denied.SRSRSRPReferenceErrorIdentifier=="sixgr:truth:SRSIsolationEvidence");
badItem=item; badItem.Context.SRSComponentBinding.ConfigurationEpoch= ...
    badItem.Context.SRSComponentBinding.ConfigurationEpoch+1;
