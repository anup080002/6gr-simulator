function folder=diagnoseH4100MeasuredULGrant(soundingFolder)
% Retained measured SRS -> production AMC/grant -> independently received DCI
% -> UE-owned PUSCH. Control is a real independent CDL/RF episode, not a
% continuation of the sounding clock. This is a repair diagnostic, not a
% scenario, throughput population, or statistical acceptance result.
setup6GRSimToolkit('Verbose',false);
inputs=fullfile(string(soundingFolder),["configuration.mat","receptions.mat","adaptation_replay.mat"]);
assert(all(isfile(inputs)),'test:MissingPhysicalSRS','Require a completed measured SRS replay.');
inputHashes=arrayfun(@(p)string(sixgr.util.sha256File(p)),inputs);
saved=load(inputs(1),'cfg'); measured=load(inputs(2),'receptions');
replayed=load(inputs(3),'feedback','rows','paths','hashes');
assert(numel(measured.receptions)==2 && height(replayed.rows)==2 && ...
    all(~replayed.rows.ScenarioAccepted) && all(~replayed.rows.StatisticallyQualified));
for n=1:numel(replayed.paths)
    assert(replayed.hashes(n)==string(sixgr.util.sha256File(replayed.paths(n))), ...
        'test:ChangedSoundingSource','Do not silently replay a different source version.');
end
feedback=replayed.feedback{end}; observation=measured.receptions{end};
assert(feedback.Valid && feedback.SourceSlot==observation.SourceSlot && ...
    feedback.RI==observation.Output.RIEstimate && feedback.PMI==observation.Output.TPMIEstimate);
policyFile='simulator/configs/validation/h4_100_installed_pdcch_development.yaml';
policy=sixgr.lls6g.config.readConfigFile(policyFile);
episode=policy.cases(string({policy.cases.id})=="present_uplink_grant");
assert(isscalar(episode));
folder=fullfile(pwd,'results','diagnostics','h4_measured_ul_grant', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
assert(~isfolder(folder)); mkdir(folder);
cfg=saved.cfg; cfg.run.rootRunFolder=folder;
cfg=sixgr.truth.attachFixedLinkRuntimeAntennaContext(cfg,policy.ue_index,policy.serving_cell);
scope="measured_SRS_API_replay_to_independent_control_and_UE_TX_not_continuous_runtime";
files=[string(mfilename('fullpath'))+".m"; string(policyFile); ...
    string(which('sixgr.l2.mac.SchedulerBase')); ...
    string(which('sixgr.link.runIndependentPDCCHReceiverEpisode')); ...
    string(which('sixgr.link.transmitReceivedPUSCH')); ...
    string(which('sixgr.phy.ul.PUSCH_Tx')); ...
    string(which('sixgr.phy.pdcch.connectedDataAllocation'))];
hashes=arrayfun(@(p)string(sixgr.util.sha256File(p)),files);
save(fullfile(folder,'sources.mat'),'inputs','inputHashes','files','hashes','scope');
% Resolve legal configured timing at the actual delivery boundary. Never
% freshen an old measurement or substitute a convenient source/delivery slot.
controlSlot=feedback.DeliveredSlot;
probe=struct('Direction','UL','ControlAbsoluteSlot',controlSlot-1, ...
    'ControlSymbolAllocation',cfg.phy.pdcch.symbolAllocation, ...
    'SymbolAllocation',cfg.phy.pusch.symbolAllocation,'HARQProcess',0);
decision=sixgr.phy.frame.TimingRelationEngine.resolveProductionGrant(cfg,probe);
save(fullfile(folder,'timing.mat'),'decision','feedback','controlSlot');
assert(decision.Valid,'test:MeasuredSRSNoLegalULOpportunity', ...
    'Measured delivery has no legal installed K2 opportunity: %s',decision.ReasonCode);
dataSlot=double(decision.DataAbsoluteSlot)+1;
assert(dataSlot-feedback.SourceSlot<=cfg.run.controlGating.srsMaxAgeSlots, ...
    'test:MeasuredSRSStaleAtData','Do not relax the configured SRS age for a data grant.');
dataCfg=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,dataSlot);
p=dataCfg.phy.pusch;
grant=struct('Direction',"UL",'Frame',1,'Slot',dataSlot, ...
    'ControlAbsoluteSlot',controlSlot-1,'RNTI',double(p.RNTI), ...
    'UEIndex',policy.ue_index,'ServingCell',policy.serving_cell, ...
    'PRBSet',double(p.prbSet),'SymbolAllocation',double(p.symbolAllocation), ...
    'NumLayers',double(p.numLayers),'Layers',double(p.numLayers), ...
    'MCSIndex',double(p.mcsIndex),'MCS',double(p.mcsIndex), ...
    'Modulation',string(p.modulation),'TargetCodeRate',double(p.codeRate), ...
    'HARQ',struct('HarqID',0,'NDI',true,'RV',0,'IsRetransmission',false));
grant=sixgr.truth.CoupledTruthRuntime.applyMeasuredFeedbackAMCToGrantRuntime( ...
    grant,feedback,[],dataCfg,'UL');
grant.TPMI=feedback.PMI; grant.SRSValid=true; grant.SRSCausalUsable=true;
grant.SRSCausalMeasurementId="retained_actual_SRS_SHA256:"+inputHashes(2);
grant.LastSuccessfulSRSSlot=feedback.SourceSlot;
grant.SRSAgeSlots=dataSlot-feedback.SourceSlot;
scheduler=sixgr.l2.mac.SchedulerPF(dataCfg,'Direction','UL');
grant=scheduler.attachCanonicalTimingDecision(grant);
grant=scheduler.finalizeExactPHYFeasibility(grant);
assert(grant.ExactPHYFeasible && grant.Valid,'test:MeasuredULInfeasible', ...
    'Actual measured decision failed exact allocation: %s', ...
    string(sixgr.util.structGet(grant,'ExactPHYInfeasibilityReason','')));
grant.DCI=scheduler.buildDCIBitfield(grant);
frozen=sixgr.phy.grant.freezePHYGrant(dataCfg,'UL',grant);
save(fullfile(folder,'scheduled_grant.mat'),'dataCfg','grant','frozen','feedback','scope','-v7.3');
fprintf('H4_MEASURED_UL_GRANT control=%g data=%g source=%g rank=%g MCS=%g PRB=%g\n', ...
    controlSlot,dataSlot,feedback.SourceSlot,grant.NumLayers,grant.MCSIndex,numel(grant.PRBSet));
controlCfg=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,controlSlot);
controlCfg.lls6g.userContext.RuntimeSlotStartTime_s=(controlSlot-1)*sixgr.time.slotDurationSec(cfg);
prepared=sixgr.link.prepareSharedPDCCHTransmission(controlCfg, ...
    'Grant',grant,'DCIBits',grant.DCI.Bits,'RNTI',grant.RNTI);
design=struct('EpisodeID',"actual_SRS_scheduled_UL_DCI", ...
    'UEIndex',policy.ue_index,'ServingCell',policy.serving_cell, ...
    'ChannelSeed',episode.channel_seed,'NoiseSeed',episode.noise_seed, ...
    'GuardSamples',policy.guard_samples,'SignalPresent',true, ...
    'AbsoluteSlot0',controlSlot-1,'TimingBoundary',string(policy.timing_boundary));
out=sixgr.link.runIndependentPDCCHReceiverEpisode(controlCfg,prepared,design,fullfile(folder,'control'));
assert(out.Events.ExactPayloadRecovered==1,'test:MeasuredULControlFailed', ...
    'Preserve the actual control failure; do not tune its seed or threshold.');
assignment=sixgr.phy.pdcch.materializeConnectedDCI(out.Receiver,out.ReceiverInfo,controlCfg);
assert(assignment.Direction=="UL" && assignment.NumLayers==grant.NumLayers && ...
    assignment.TPMI==grant.TPMI && assignment.MCS==grant.MCSIndex && ...
    assignment.DataAbsoluteSlot==dataSlot-1);
allocation=sixgr.phy.pdcch.connectedDataAllocation(controlCfg,assignment);
prior=rng; cleanup=onCleanup(@()rng(prior)); %#ok<NASGU>
rng(double(cfg.run.seed),'twister');
payload=int8(randi([0 1],allocation.NominalTBSBits,1));
ue=sixgr.link.ReceivedULHARQState(controlCfg);
[tx,txInfo,ue]=ue.transmit(controlCfg,assignment,payload,[]); %#ok<ASGLU>
assert(tx.PrecodeInfo.AuthoritativeDCIDecisionUsed && ...
    ~tx.PrecodeInfo.AuthoritativeSRSDecisionUsed && ...
    tx.TransportBlockSize==frozen.CodingLayout.TBSBits && ...
    tx.PUSCH.NumLayers==grant.NumLayers && size(tx.Waveform,2)==4 && ...
    isequal(tx.TransportBlock,payload),'test:MeasuredULTransmissionMismatch');
save(fullfile(folder,'received_grant_transmitter.mat'), ...
    'controlCfg','assignment','allocation','tx','txInfo','payload','ue','scope','-v7.3');
row=table(feedback.SourceSlot,feedback.DeliveredSlot,controlSlot,dataSlot, ...
    feedback.RI,feedback.PMI,feedback.CQI,grant.MCSIndex,string(grant.Modulation), ...
    grant.TargetCodeRate,numel(grant.PRBSet),tx.TransportBlockSize, ...
    true,true,false,false,false,scope, ...
    'VariableNames',{'SRSSourceSlot','SRSReplayDeliverySlot','ControlSlot','DataSlot', ...
    'Rank','TPMI','SchedulerCQI','MCS','Modulation','CodeRate','NumPRB','TBSBits', ...
    'PhysicalPDCCHDecoded','ReceivedDCIPUSCHTransmitted','PUSCHReceived', ...
    'ScenarioAccepted','StatisticallyQualified','Scope'});
sixgr.util.csvWriteTable(fullfile(folder,'measured_ul_grant.csv'),row,'PreserveSchema',true);
assert(isequal(hashes,arrayfun(@(p)string(sixgr.util.sha256File(p)),files)) && ...
    isequal(inputHashes,arrayfun(@(p)string(sixgr.util.sha256File(p)),inputs)), ...
    'test:MeasuredULSourcesChanged');
fprintf('H4_MEASURED_UL_GRANT_PASS folder=%s PUSCH_RX=0 scenario_accepted=0\n',folder);
end
