function test_c0_declaration_and_pbch_populations()
%TEST_C0_DECLARATION_AND_PBCH_POPULATIONS No forced PCI and PBCH-A coverage.
[cfg,~]=sixgr.phy.ia.c0.config.loadScenario( ...
    "simulator/configs/initial_access/c0/C0.yaml","smoke");
b=sixgr.phy.ia.c0.waveform.buildNRAnchorA(cfg,"PayloadSeed",9580);
rx=repmat(b.Waveform,1,double(cfg.mimo.num_rx_antennas));
prefix=sum(double(b.OFDMInfo.SymbolLengths(1:b.CandidateStartSymbol)));
blocked=struct("PSSStageThreshold",Inf,"GlobalDeclarationThreshold",Inf);
r=sixgr.phy.ia.c0.receiver.runCompleteSSBReceiver( ...
    rx,b,cfg,blocked,"TrueCFOHz",0,"TrueTimingSamples",prefix);
assert(r.NoCellDeclared&&~r.CorrectPCIDeclared&&~r.WrongPCIDeclared);
assert(double(r.NoCellDeclared)+double(r.CorrectPCIDeclared)+ ...
    double(r.WrongPCIDeclared)==1);
trial=sixgr.phy.ia.c0.campaigns.runC0Trial(b,cfg,-20,2,blocked);
assert(trial.PBCHComponentAttempted, ...
    "PBCH-A must include every realization independent of declaration.");
assert(~trial.PBCHConditionalAttempted, ...
    "PBCH-B must remain conditioned on correct practical joint acquisition.");
assert(trial.NoCellDeclared&&~trial.WrongPCIDeclared);
confirmationBlocked=struct("PSSStageThreshold",-Inf, ...
    "GlobalDeclarationThreshold",Inf);
confirmationTrial=sixgr.phy.ia.c0.campaigns.runC0Trial( ...
    b,cfg,20,3,confirmationBlocked);
assert(confirmationTrial.ConditionalSSSEligible&& ...
    ~confirmationTrial.ConditionalSSSSuccess, ...
    "A calibrated SSS declaration-stage failure must count as a conditional SSS error.");
fprintf('test_c0_declaration_and_pbch_populations: PASS\n');
end
