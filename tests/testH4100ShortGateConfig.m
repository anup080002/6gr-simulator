function ok = testH4100ShortGateConfig()
%TESTH4100SHORTGATECONFIG Shorten the horizon without changing the PHY.
setup6GRSimToolkit('Verbose',false);
root=fullfile('simulator','configs','scenarios');
parent=sixgr.lls6g.config.loadScenarioConfig(fullfile(root, ...
    'h4_100_cdlc100_connected_impaired_40db_gate.yaml'));
short=sixgr.lls6g.config.loadScenarioConfig(fullfile(root, ...
    'h4_100_cdlc100_connected_impaired_40db_short.yaml'));

assert(parent.get('run_control.total_slots')==200, ...
    'The original long gate must remain available.');
assert(short.get('run_control.total_slots')==60 && ...
    short.get('run_control.total_time_ms')==30 && ...
    short.get('run_control.measurement_slots')==60 && ...
    short.get('run_control.measurement_time_ms')==30 && ...
    short.get('simulation.n_frames')==3 && ...
    short.get('simulation.n_slots')==60 && ...
    short.get('simulation.n_subframes')==30 && ...
    short.get('simulation.min_duration_s')==0.03 && ...
    short.get('random_access.num_slots')==60 && ...
    short.get('random_access.num_subframes')==30, ...
    'All short-run duration owners must describe the same 30-ms clock.');
assert(short.get('simulation.random_seed')==parent.get('simulation.random_seed') && ...
    short.get('run_control.seed')==parent.get('run_control.seed'), ...
    'The shortened run must retain the original random realization.');

% Compare the complete resolved objects after removing ONLY the deliberately
% changed fields. This guards control/feedback, impairments, thresholds,
% output fidelity, traffic, seeds and initial-access requirements together.
parentData=parent.toStruct(); shortData=short.toStruct();
parentData.meta=rmfield(parentData.meta,{'scenario_id','description','purpose'});
shortData.meta=rmfield(shortData.meta,{'scenario_id','description','purpose'});
runDurationFields={'total_slots','total_time_ms','measurement_slots','measurement_time_ms'};
parentData.run_control=rmfield(parentData.run_control,runDurationFields);
shortData.run_control=rmfield(shortData.run_control,runDurationFields);
durationFields={'n_frames','n_slots','n_subframes','min_duration_s'};
parentData.simulation=rmfield(parentData.simulation,durationFields);
shortData.simulation=rmfield(shortData.simulation,durationFields);
parentData.random_access=rmfield(parentData.random_access,{'num_slots','num_subframes'});
shortData.random_access=rmfield(shortData.random_access,{'num_slots','num_subframes'});
parentData.output=rmfield(parentData.output,'profile');
shortData.output=rmfield(shortData.output,'profile');
% Provenance legitimately includes the extra child YAML. Check that exact
% additional source, then exclude only path provenance from PHY equality.
assert(isequal(short.SourceFiles(1:end-1),parent.SourceFiles) && ...
    short.SourceFiles(end)==short.ConfigPath, ...
    'The short gate must inherit the same sources plus its own YAML.');
parentData.config_inheritance=rmfield(parentData.config_inheritance,{'parents','provenance'});
shortData.config_inheritance=rmfield(shortData.config_inheritance,{'parents','provenance'});
assert(isequaln(parentData,shortData), ...
    'The short gate must change only duration and descriptive identity, not PHY or acceptance policy.');

cfg=sixgr.lls6g.buildInternalConfig(short, ...
    fullfile(tempdir,'h4_100_short_gate_config'));
assert(cfg.run.numTTI==60 && cfg.run.totalSlots==60 && ...
    cfg.run.totalTime_ms==30 && cfg.run.measurementSlots==60 && ...
    cfg.run.measurementTime_ms==30 && cfg.run.numFrames==3, ...
    'The production runtime must execute and measure the same shortened horizon.');
prach=sixgr.rach.PRACHConfig(cfg,'NumPRACHOccasions',1,'NumTrials',1);
assert(prach.NumSlots==60 && prach.NumSubframes==30 && ...
    prach.CarrierSCSkHz==30 && prach.NSizeGrid==273 && ...
    prach.NumRxAntennas==64 && prach.NumTxAntennas==4 && ...
    double(prach.FirstActiveOccasion.SlotIndex1)==10, ...
    'Shortening must preserve the native H4 access occasion and dimensions.');
assert(cfg.phy.nTxAnt==64 && cfg.phy.nRxAnt==4 && ...
    cfg.phy.pdsch.maxRankDefault==4 && cfg.phy.pusch.maxRankDefault==4 && ...
    cfg.phy.csirs.numResources==8 && cfg.channel.snr_dB==40, ...
    'The short gate must retain full H4 spatial capability and the 40-dB point.');
period=double(cfg.phy.csi.reportPeriodicitySlots);
offset=double(cfg.phy.csi.reportOffsetSlots);
assert(isequal((offset:period:59)+1,[19 39 59]), ...
    'All three original CSI reporting occasions must remain within the short horizon.');
for firstSlot=[7 27 47]
    window=sixgr.truth.resolveTRSObservationWindow(cfg,firstSlot);
    assert(window.ObservationStarts && ...
        isequal(window.AbsoluteSlotNumbers,[firstSlot-1 firstSlot]), ...
        'TRS tracking cadence must not be compressed to shorten the run.');
end
ok=true;
disp('H4_100_SHORT_GATE_CONFIG_PASS slots=60 duration_ms=30 scenario_accepted=0');
end
