function ok=testRAN1AI1032ReferenceArithmetic()
%TESTRAN1AI1032REFERENCEARITHMETIC Independent fixed-input TDoc arithmetic.
% This verifies a construction identity, never an observed CRC/BLER point.
Qm=8; layers=2; prbs=51; nrePerPRB=144; rate=948/1024;
nInfo=prbs*nrePerPRB*layers*Qm*rate;
assert(nInfo==108783,'sixgr:ran1ai1032:ReferenceNInfo', ...
    'The contribution''s 51-PRB N_info fixture changed.');
n=max(3,floor(log2(nInfo-24))-5);
nInfoPrime=max(3840,2^n*round((nInfo-24)/2^n));
assert(nInfoPrime==108544,'sixgr:ran1ai1032:ReferenceNInfoPrime', ...
    'The independently computed high-N_info quantization changed.');
codeBlocksForTBS=ceil((nInfoPrime+24)/(8448-24));
tbs=8*codeBlocksForTBS*ceil((nInfoPrime+24)/(8*codeBlocksForTBS))-24;
assert(codeBlocksForTBS==13 && tbs==108552 && ...
    double(nrTBS('256QAM',layers,prbs,nrePerPRB,rate,0))==tbs, ...
    'sixgr:ran1ai1032:ReferenceTBS', ...
    'The independent arithmetic, supplied fixture and toolbox TBS disagree.');
tbWithCRC=tbs+24;
cbCount=ceil(tbWithCRC/(8448-24));
allCRC=tbWithCRC+24*cbCount;
kPrime=allCRC/cbCount;
lifting=384;
filler=22*lifting-kPrime;
assert(tbWithCRC==108576 && cbCount==13 && allCRC==108888 && ...
    kPrime==8376 && filler==72, ...
    'sixgr:ran1ai1032:ReferenceLDPCLayout', ...
    'The supplied BG1 segmentation/lifting fixture changed.');
g51=51*nrePerPRB*layers*4;
g120=120*nrePerPRB*layers*4;
assert(g51==58752 && g120==138240 && ...
    abs(tbs/g51-1.84763)<1e-5 && ...
    abs(tbs/g120-0.785243)<1e-6 && ...
    abs(allCRC/g120-0.787674)<1e-6, ...
    'sixgr:ran1ai1032:ReferenceCodedBits', ...
    'The reference coded-bit and payload ratios changed.');
fprintf('RAN1_AI1032_REFERENCE_ARITHMETIC_PASS TBS=%d BG1_CB=%d G51=%d G120=%d\n', ...
    tbs,cbCount,g51,g120);
ok=true;
end
