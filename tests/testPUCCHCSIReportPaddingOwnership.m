function ok = testPUCCHCSIReportPaddingOwnership()
%TESTPUCCHCSIREPORTPADDINGOWNERSHIP Separate wire padding from CSI bits.

setup6GRSimToolkit("Verbose", false);

part1 = int8([1; 0; 1; 1; 0]);
part2 = int8([0; 1]);
report = sixgr.phy.pucch.UCIReport(struct( ...
    "ReportID", "CSI-PADDING-REGRESSION", "RNTI", 1, ...
    "ServingCell", 1, "ComponentCarrier", 0, "ULBWP", 0, ...
    "ConfigurationEpoch", 1, "TargetSlot", 14, "PriorityIndex", 0, ...
    "HARQACKReport", struct([]), "SchedulingRequestReports", struct([]), ...
    "CSIReports", struct("Part1Bits", part1, "Part2Bits", part2, ...
    "Priority", 0, "ReportID", 1), ...
    "ReportSource", "focused_runtime_regression", ...
    "TriggeringEventIDs", "CSI-PADDING-REGRESSION"));
serialized = sixgr.phy.pucch.UCIReportSerializer.serialize(report);
wireBits = [serialized.Sequence1.Bits; serialized.Sequence2.Bits];
assert(numel(wireBits) == 8 && serialized.PaddingBitCount == 1, ...
    "The 5+2 CSI report must expose its serializer-owned wire padding bit.");

decoded = sixgr.phy.pucch.UCIReportSerializer. ...
    extractDecodedInformationBits(serialized, wireBits);
assert(isequal(decoded.CSIPart1Bits, part1) && ...
    isequal(decoded.CSIPart2Bits, part2) && ...
    numel(decoded.InformationBits) == 7 && ...
    numel(decoded.PaddingBits) == 1, ...
    "CSI delivery must remove only layout-owned padding and preserve report bits.");

didThrow = false;
try
    sixgr.phy.pucch.UCIReportSerializer. ...
        extractDecodedInformationBits(serialized, wireBits(1:end-1));
catch ME
    didThrow = strcmp(ME.identifier, "sixgr:phy:pucch:UCILengthMismatch");
end
assert(didThrow, ...
    "A truncated physical PUCCH payload must fail closed at the layout boundary.");

ok = true;
fprintf("testPUCCHCSIReportPaddingOwnership: PASS\n");
end
