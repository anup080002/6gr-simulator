function ok = testPDSCHMultiPortPrecoding()
%TESTPDSCHMULTIPORTPRECODING Regression checks for explicit DL precoding.

setup6GRSimToolkit("Verbose", false);
if ~localHaveRequired5G()
    error("sixgr:test:Required5GToolboxUnavailable", ...
        ["testPDSCHMultiPortPrecoding requires the 5G Toolbox APIs " ...
        "checked by localHaveRequired5G; unavailable tests cannot pass."]);
end

cfg = sixgr.config.defaultConfig();
% Isolated narrow-carrier PDSCH calibration; no SS/PBCH is transmitted here.
% SSB reservation/collision coverage remains in testSSBPRBSymbolReservation.
cfg.phy.ssb.enable = false;
cfg.run.shortRun = true;
cfg.run.pdschExecutionProfile = "phy_calibration";
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.phy.carrier.NSizeGrid = 18;
cfg.phy.pdsch.prbSet = 0:7;
cfg.phy.pdsch.symbolAllocation = [0 10];
cfg.phy.pdsch.modulation = 'QPSK';
cfg.phy.pdsch.codeRate = 0.35;
cfg.phy.pdsch.mcsTable = "calibration_explicit";
cfg.phy.pdsch.mcsIndex = 0;
cfg.phy.pdsch.executionProfile = "phy_calibration";
cfg.phy.pdsch.mcsContext = localCalibrationMCSContext();
cfg.phy.pdsch.nLayers = 2;
cfg.phy.pdsch.numLayers = 2;
cfg.phy.pdsch.enablePTRS = false;
cfg.phy.csirs.enable = false;
cfg.phy.nTxAnt = 4;
cfg.channel.nTxAnt = 4;

W = [ ...
    1  0; ...
    0  1; ...
    1  1; ...
    1 -1];

[tx, txInfo] = sixgr.phy.dl.PDSCH_Tx(cfg, "PrecodingMatrix", W);
portContract = txInfo.ResourceGridPortContract;
assert(logical(txInfo.Precoding.Active), "Multi-layer DL path must enable explicit precoding.");
assert(string(txInfo.Precoding.Mode) == "explicit-wideband", "Unexpected explicit precoding mode.");
assert(string(txInfo.Precoding.Source) == "explicit-matrix", "Explicit matrix source was not recorded.");
assert(txInfo.Precoding.NumLayers == 2, "Unexpected layer count in precoding info.");
assert(txInfo.Precoding.NumPorts == 4, "Unexpected antenna-port count in precoding info.");
assert(size(tx.Grid, 3) >= 4, ...
    "Precoded PDSCH grid must expose at least the four antenna ports used by explicit PDSCH precoding.");
assert(size(tx.PDSCHAntennaIndices, 2) == 4, "Precoded PDSCH indices must be antenna-oriented.");
assert(size(tx.DMRSAntennaIndices, 2) == 4, "Precoded DMRS indices must be antenna-oriented.");
assert(portContract.PDSCHAntennaPortCount == 4 && portContract.DMRSAntennaPortCount == 4, ...
    "Port contract must report the true PDSCH and DM-RS antenna-port counts.");
assert(logical(portContract.PrecodingPortAlignmentOk) && logical(portContract.PDSCHDMRSPortAlignmentOk), ...
    "Port contract must confirm truthful precoding and DM-RS alignment.");
assert(logical(portContract.ResourceSelectiveChannelEstimateRequired), ...
    "Multi-port DL mapping must require resource-selective channel estimation.");
assert(portContract.GridNumPages >= portContract.PrimarySignalPortCount, ...
    "Full transmit-grid page count must never under-report the primary signal ports.");

portSym = nrPDSCH(tx.Carrier, tx.PDSCH, {tx.Codeword});
[expAntSym, expAntInd] = nrPDSCHPrecode(tx.Carrier, portSym, tx.PDSCHIndices, txInfo.Precoding.MatrixNR);
assert(isequal(tx.PDSCHAntennaIndices, expAntInd), ...
    "PDSCH antenna indices do not match the explicit precoding stage.");
assert(max(abs(tx.PDSCHAntennaSymbols(:) - expAntSym(:))) < 1e-10, ...
    "PDSCH antenna symbols do not match the explicit precoding stage.");

cfgReserved = cfg;
cfgReserved.phy.csirs.enable = true;
cfgReserved.phy.csirs.nPorts = 1;
cfgReserved.phy.csirs.rowNumber = 2;
cfgReserved.phy.csirs.rbOffset = 0;
cfgReserved.phy.csirs.numRB = 7;
cfgReserved.phy.csirs.symbolLocations = 5;
cfgReserved.phy.csirs.subcarrierLocations = 0;
cfgReserved.phy.csirs.period_slots = 10;
cfgReserved.phy.csirs.offset_slots = 0;
[txReserved, ~] = sixgr.phy.dl.PDSCH_Tx(cfgReserved, "PrecodingMatrix", W);
assert(size(txReserved.PDSCHSymbols, 1) == size(txReserved.PDSCHIndices, 1), ...
    "Reserved-resource PDSCH rate matching must generate one symbol per scheduled data RE.");
assert(size(txReserved.PDSCHAntennaSymbols, 1) == size(txReserved.PDSCHAntennaIndices, 1), ...
    "Reserved-resource PDSCH precoding must preserve symbol/index size equality.");
assert(numel(txReserved.Codeword) == double(txReserved.G), ...
    "Reserved-resource PDSCH codeword length must use the exact nrPDSCHIndices data-bit budget.");

% A shared-slot user-dedicated component must reserve the configured
% serving-cell CSI-RS REs without transmitting another copy.  Otherwise
% every scheduled MU user injects the same common signal outside its frozen
% PDSCH precoder and the physical sample-domain MU isolation is destroyed.
[txDedicated, dedicatedInfo] = sixgr.phy.dl.PDSCH_Tx(cfgReserved, ...
    "PrecodingMatrix", W, ...
    "CellCommonSignalOwnershipMode", "reserve_only");
assert(isequal(txDedicated.CSIRSIndices, txReserved.CSIRSIndices) && ...
    numel(txDedicated.Codeword) == numel(txReserved.Codeword), ...
    "Reserve-only common-signal ownership must preserve CSI-RS RE reservation and PDSCH rate matching.");
assert(logical(txDedicated.CSIRSRuntimeEvent.Scheduled) && ...
    ~logical(txDedicated.CSIRSRuntimeEvent.Transmitted) && ...
    string(txDedicated.CSIRSRuntimeEvent.CellCommonSignalOwnershipMode) == "reserve_only" && ...
    string(txDedicated.CSIRSRuntimeEvent.RuntimeMaterializationStatus) == ...
    "reserved_only_serving_cell_common_plane_owned_elsewhere", ...
    "User-dedicated shared-slot PDSCH must truthfully report reserved, nonduplicated CSI-RS ownership.");
Q = orth(double(W));
dedicatedProjection = double(txDedicated.Waveform) * conj(Q) * Q.';
dedicatedResidual = norm(double(txDedicated.Waveform) - dedicatedProjection, "fro") / ...
    max(norm(double(txDedicated.Waveform), "fro"), realmin);
assert(dedicatedResidual < 1e-10 && ...
    string(dedicatedInfo.CSIRSRuntimeEvent.CellCommonSignalOwnershipMode) == "reserve_only", ...
    "A user-dedicated PDSCH component must remain inside its explicit frozen spatial subspace.");
try
    sixgr.phy.dl.PDSCH_Tx(cfgReserved, "PrecodingMatrix", W, ...
        "CellCommonSignalOwnershipMode", "invalid");
    error("testPDSCHMultiPortPrecoding:MissingCommonSignalOwnershipGuard", ...
        "Expected invalid common-signal ownership mode to fail.");
catch ME
    assert(strcmp(ME.identifier, "sixgr:pdsch:InvalidCellCommonSignalOwnershipMode"), ...
        "Unexpected common-signal ownership guard failure: %s", ME.identifier);
end

[rx, info] = sixgr.phy.dl.PDSCH_Rx(tx.Waveform, cfg, ...
    "Carrier", tx.Carrier, ...
    "PDSCH", tx.PDSCH, ...
    "PDSCHIndices", tx.PDSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "CodingPlan", tx.CodingPlans, ...
    "PrecodingMatrix", W);

assert(rx.Ok, "Explicitly precoded multi-port PDSCH must decode successfully.");
assert(isequal(int8(rx.TransportBlock(:)), int8(tx.TransportBlock(:))), ...
    "Explicitly precoded multi-port PDSCH changed the recovered transport block.");
assert(rx.MeasuredDMRSPortCount == 2 && ...
    string(rx.MeasuredDMRSPortSet) == ...
    string(mat2str(double(tx.PDSCH.DMRS.DMRSPortSet(:).'))) && ...
    string(rx.MeasuredDMRSPortSetSource) == ...
    "executed_nrPDSCHConfig.DMRS.DMRSPortSet", ...
    "PDSCH receiver evidence must retain the executed logical DM-RS " + ...
    "port identity separately from the measured count.");
assert(strcmp(string(info.ChannelEstimation.EngineUsed), "nrChannelEstimate") && ...
    ~logical(info.ChannelEstimation.ScalarFastPathUsed), ...
    "Explicitly precoded multi-port PDSCH must stay on resource-selective channel estimation.");

% A shared-slot interferer is supplied as exact receiver-sample evidence.
% The canonical receiver must demodulate it onto the victim data REs and
% use the measured covariance in its LMMSE-IRC solve.
interferenceGrid = complex(zeros(size(tx.Grid)));
plane = tx.Carrier.NSizeGrid * 12 * tx.Carrier.SymbolsPerSlot;
baseDataIndices = unique(mod(double(tx.PDSCHIndices(:))-1,plane)+1,"stable");
rs = RandStream("mt19937ar","Seed",6197);
peerSymbols = (2*(rand(rs,numel(baseDataIndices),1)>0.5)-1 + ...
    1i*(2*(rand(rs,numel(baseDataIndices),1)>0.5)-1))/sqrt(2);
peerSpatial = [1;1i;-1;exp(1i*pi/3)]/2;
for port = 1:4
    page = interferenceGrid(:,:,port);
    page(baseDataIndices) = 0.15 * peerSpatial(port) .* peerSymbols;
    interferenceGrid(:,:,port) = page;
end
peerWaveform = nrOFDMModulate(tx.Carrier,interferenceGrid);
peerTensor = reshape(peerWaveform,size(peerWaveform,1),size(peerWaveform,2),1);
[rxIRC, ~] = sixgr.phy.dl.PDSCH_Rx(tx.Waveform + peerWaveform, cfg, ...
    "Carrier", tx.Carrier, "PDSCH", tx.PDSCH, ...
    "PDSCHIndices", tx.PDSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, "RV", tx.RV, ...
    "CodingPlan", tx.CodingPlans, "PrecodingMatrix", W, ...
    "InterferenceContributionTensor", peerTensor, ...
    "InterferenceContributionSource", "unit_test_exact_shared_slot_peer", ...
    "InterferenceContributionDomain", "receiver_sample_waveform_pre_noise");
assert(logical(rxIRC.InterferenceCovarianceAvailable) && ...
    string(rxIRC.InterferenceCovarianceSource) == ...
    "oracle_separated_shared_slot_per_prb_symbol_contribution_grid_covariance", ...
    "PDSCH receiver must materialize covariance from exact shared-slot samples.");
assert(contains(string(rxIRC.EqualizerInfo.EngineUsed),"lmmse_irc") && ...
    logical(rxIRC.EqualizerInfo.InterferenceCovarianceAvailable) && ...
    isfinite(double(rxIRC.MeasuredInterferenceCovarianceTrace)) && ...
    double(rxIRC.MeasuredInterferenceCovarianceTrace) > 0, ...
    "PDSCH equalizer must consume the measured covariance and export its trace.");

cfgGuard = cfg;
cfgGuard.phy.pdsch.numCodewords = 2;
try
    sixgr.phy.dl.PDSCH_Tx(cfgGuard, "PrecodingMatrix", W);
    error("testPDSCHMultiPortPrecoding:MissingGuard", ...
        "Expected invalid rank/codeword mapping to fail.");
catch ME
    assert(strcmp(ME.identifier, "sixgr:phy:dl:PDSCHCodewordLayerScope"), ...
        "Unexpected guard failure for invalid codeword-layer mapping: %s", ME.identifier);
end

ok = true;
end

function context = localCalibrationMCSContext()
context = struct( ...
    "UECapability1024QAM", false, ...
    "RRCEnabled1024QAM", false, ...
    "DCIEnabled1024QAM", false, ...
    "DeploymentAllows1024QAM", false, ...
    "FrequencyRangeAllows1024QAM", false, ...
    "BandAllows1024QAM", false, ...
    "FrequencyRange", "FR1", ...
    "OperatingBand", "n78", ...
    "DeploymentClass", "controlled_test");
end

function tf = localHaveRequired5G()
tf = exist("nrPDSCH", "file") == 2 ...
    && exist("nrPDSCHDecode", "file") == 2 ...
    && exist("nrPDSCHPrecode", "file") == 2 ...
    && exist("nrChannelEstimate", "file") == 2;
end
