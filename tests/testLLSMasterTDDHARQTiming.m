function ok = testLLSMasterTDDHARQTiming()
%TESTLLSMASTERTDDHARQTIMING Master YAML keeps every DDDSU DL occasion legal.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scenarios = [ ...
    "master_sinr_sweep.yaml", ...
    "master_geometry_based.yaml"];
requiresPhysicalFeedback = [false, true];
for scenarioIndex = 1:numel(scenarios)
    fileName = scenarios(scenarioIndex);
    path = fullfile(pwd, "simulator", "configs", "scenarios", fileName);
    scenario = sixgr.lls6g.config.loadScenarioConfig(path);
    raw = scenario.toStruct();
    requestedK1 = reshape(double(raw.tdd_timing.dl_harq_feedback_k1), 1, []);
    assert(isequal(requestedK1, 1:8), ...
        "%s must expose all YAML-authorized dl-DataToUL-ACK candidates 1:8.", ...
        fileName);
    cfg = sixgr.lls6g.buildInternalConfig(scenario, ...
        fullfile(tmp, erase(fileName, ".yaml")));
    appliedK1 = reshape(double(sixgr.util.structGet(cfg, ...
        "phy.tddTiming.dlHARQFeedbackK1Candidates", [])), 1, []);
    assert(isequal(appliedK1, requestedK1), ...
        "%s K1 candidates must reach the canonical timing policy unchanged.", ...
        fileName);
    policyK1 = reshape(double(cfg.phy.frameStructure.TimingContext.Policy.AllowedK1), 1, []);
    assert(isequal(policyK1, requestedK1), ...
        "%s frame timing policy must preserve the master-YAML K1 list.", ...
        fileName);

    % The fixed-link calibration master intentionally disables PUCCH and
    % HARQ.  Its responsibility here is to preserve the operator's timing
    % candidates, not to invent an ACK resource.  Connected scenarios that
    % enable PUCCH must prove that every DL slot in DDDSU has a legal ACK.
    if ~requiresPhysicalFeedback(scenarioIndex)
        continue;
    end

    for absoluteSlot0 = 0:3
        partition = sixgr.util.resolveTDDSlotPartition(cfg, absoluteSlot0);
        slotDLAllocation = reshape(double(partition.DLSymbolAllocation), 1, []);
        configuredDLAllocation = reshape(double(sixgr.util.structGet(cfg, ...
            "phy.pdsch.SymbolAllocation", sixgr.util.structGet(cfg, ...
            "phy.pdsch.symbolAllocation", []))), 1, []);
        dlStart = max(slotDLAllocation(1), configuredDLAllocation(1));
        dlEnd = min(sum(slotDLAllocation), sum(configuredDLAllocation));
        dlAllocation = [dlStart, max(0, dlEnd - dlStart)];
        assert(numel(dlAllocation) == 2 && dlAllocation(2) > 0, ...
            "DDDSU slot %d must expose a DL symbol allocation.", absoluteSlot0 + 1);
        grant = struct( ...
            "Direction", "DL", ...
            "ControlAbsoluteSlot", absoluteSlot0, ...
            "ControlSymbolAllocation", [0 min(2, dlAllocation(2))], ...
            "SymbolAllocation", dlAllocation, ...
            "HARQProcess", 0);
        decision = sixgr.phy.frame.TimingRelationEngine. ...
            resolveProductionGrant(cfg, grant);
        assert(logical(decision.Valid), ...
            "%s DDDSU DL slot %d has no legal configured HARQ-ACK timing: %s", ...
            fileName, absoluteSlot0 + 1, string(decision.ReasonCode));
        feedbackSlot = double(decision.FeedbackAbsoluteSlot);
        assert(double(decision.K1) == feedbackSlot - absoluteSlot0, ...
            "%s DDDSU DL slot %d selected unexpected K1=%g.", ...
            fileName, absoluteSlot0 + 1, double(decision.K1));
        assert(ismember(double(decision.K1), requestedK1), ...
            "%s DDDSU DL slot %d selected a K1 outside YAML authority.", ...
            fileName, absoluteSlot0 + 1);
        feedbackAllocation = reshape(double(cfg.phy.pucch. ...
            harqACKSymbolAllocation), 1, []);
        feedbackPartition = sixgr.util.resolveTDDSlotPartition( ...
            cfg, feedbackSlot);
        ulAllocation = reshape(double( ...
            feedbackPartition.ULSymbolAllocation), 1, []);
        assert(feedbackAllocation(1) >= ulAllocation(1) && ...
            sum(feedbackAllocation) <= sum(ulAllocation), ...
            "%s DDDSU DL slot %d selected feedback slot %d, but the " + ...
            "configured PUCCH allocation is outside its UL symbols.", ...
            fileName, absoluteSlot0 + 1, feedbackSlot + 1);
    end
end

ok = true;
end
