function ok = testLLSLiveLinkAdaptationInputWarmupFiltering()
%TESTLLSLIVELINKADAPTATIONINPUTWARMUPFILTERING Exclude warmup rows from live AMC analytics when later rows exist.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

cfg = sixgr.config.defaultConfig();
cfg.outputs.saveCSV = true;

dlT = table( ...
    ["DL"; "DL"], ...
    [24; 24], ...
    [1; 2], ...
    [1; 2], ...
    [1; 1], ...
    [320; 320], ...
    [101; 101], ...
    [24; 24], ...
    [24; 24], ...
    [35; 35], ...
    [35; 35], ...
    [18; 18], ...
    ["64QAM"; "64QAM"], ...
    [0.4551; 0.4551], ...
    [0; 18], ...
    ["QPSK"; "64QAM"], ...
    [0.12; 0.4551], ...
    [0; 0], ...
    [0; 0], ...
    [1; 1], ...
    [1; 1], ...
    [5; 80], ...
    [false; false], ...
    ["siso_bypass"; "siso_bypass"], ...
    ["none"; "none"], ...
    ["OK"; "OK"], ...
    [true; false], ...
    'VariableNames', {'Direction','SNR_dB','Slot','Frame','UEIndex','RNTI','BaseStationID', ...
    'ConfiguredSNR_dB','AppliedAWGNSNR_dB','MeasuredTrialSINR_dB','ReceiverHestSINR_dB', ...
    'WidebandCQI','CQIDerivedModulation','CQIDerivedTargetCodeRate','MCSIndex','Modulation', ...
    'TargetCodeRate','PMI','CRI','RankIndicator','CRCPass','Goodput_Mbps','Crash','PrecodingMode','AppliedPrecoderSource','Status','IsWarmupFrame'});
dlT.CQIDerivedMCS = [0; 18];

artifacts = sixgr.truth.exportLLSLiveDerivedTables(cfg, tmp, struct("DL", dlT, "UL", table(), "SRS", table(), "TRS", table()), struct(), struct(), struct());
T = readtable(artifacts.LinkAdaptationInputPath, "VariableNamingRule", "preserve");

assert(height(T) == 1, "Live link-adaptation analytics must drop warmup rows when non-warmup rows exist.");
assert(double(T.MCSIndex(1)) == 18, "Live link-adaptation analytics must retain the applied non-warmup MCS row.");

staleCQI = dlT(2, :);
staleCQI.WidebandCQI = 1;
staleCQI.CQIDerivedMCS = 0;
staleCQI.CQIDerivedModulation = "QPSK";
staleCQI.CQIDerivedTargetCodeRate = 120 / 1024;
staleCQI.MCSIndex = 0;
staleCQI.PostEqSINR_dB = 21.0;
staleCQI.CQIValueSource = "not_emitted_by_active_channel_runtime_runtime";
staleCQI.CQIValueStatus = "available";
staleCQI.PostEqSINRSource = "post_equalization_sinr_from_equalizer_channel_estimate";
staleCQI.PostEqSINRValueRole = "measured_post_equalization_scheduling_input";
staleCQI.PostEqSINRValueStatus = "OK";

artifacts = sixgr.truth.exportLLSLiveDerivedTables(cfg, tmp, struct("DL", staleCQI, "UL", table(), "SRS", table(), "TRS", table()), struct(), struct(), struct());
T = readtable(artifacts.LinkAdaptationInputPath, "VariableNamingRule", "preserve");

assert(double(T.WidebandCQI(1)) > 1 && double(T.CQIDerivedMCS(1)) > 0, ...
    "Live link-adaptation analytics must replace stale not-emitted CQI=1 with measured-SINR-derived CQI/MCS.");
assert(contains(string(T.CQIValueSource(1)), "derived_from_PostEqSINR_dB"), ...
    "Backfilled live CQI must keep measured SINR provenance for WebGUI plots.");

cfgSymbol = cfg;
cfgSymbol = sixgr.util.structSet(cfgSymbol, "run.totalSlots", 2);
cfgSymbol = sixgr.util.structSet(cfgSymbol, "phy.numerology.symbolsPerSlot", 14);
cfgSymbol = sixgr.util.structSet(cfgSymbol, "phy.numerology.slotDuration_ms", 0.5);
dlSymbol = dlT(2, :);
dlSymbol.Slot = 0;
dlSymbol.SymbolStart = 2;
dlSymbol.NumSymbols = 2;
dlSymbol.TBSBits = 200;
dlSymbol.GoodBits = 100;
dlSymbol.CQIUsed = 7;
ulSymbol = dlSymbol;
ulSymbol.Direction = "UL";
ulSymbol.Slot = 1;
ulSymbol.SymbolStart = 0;
ulSymbol.NumSymbols = 14;
ulSymbol.TBSBits = 1400;
ulSymbol.GoodBits = 700;
ulSymbol.CQIUsed = 5;

artifacts = sixgr.truth.exportLLSLiveDerivedTables(cfgSymbol, tmp, struct("DL", dlSymbol, "UL", ulSymbol, "SRS", table(), "TRS", table()), struct(), struct(), struct());
S = readtable(artifacts.SymbolThroughputPath, "VariableNamingRule", "preserve");

assert(height(S) == 28, "Two 14-symbol slots must produce 28 symbol-wise throughput rows.");
dlRow = S(S.Slot == 0 & S.SymbolInSlot == 2, :);
idleRow = S(S.Slot == 0 & S.SymbolInSlot == 1, :);
ulRow = S(S.Slot == 1 & S.SymbolInSlot == 0, :);
assert(abs(double(dlRow.ScheduledDLBits(1)) - 100) < 1e-9 && ...
    abs(double(dlRow.GoodDLBits(1)) - 50) < 1e-9, ...
    "DL grant bits must be evenly assigned to the actual two-symbol allocation.");
assert(double(idleRow.TotalScheduledThroughput_Mbps(1)) == 0 && double(idleRow.TotalGrantCount(1)) == 0, ...
    "Idle symbols must remain explicit zero-bit time-axis rows.");
assert(abs(double(ulRow.ScheduledULBits(1)) - 100) < 1e-9 && ...
    abs(double(ulRow.GoodULBits(1)) - 50) < 1e-9, ...
    "UL grant bits must be evenly assigned across all fourteen UL symbols.");

% The coupled SINR-sweep runtime uses absolute campaign slots while
% run.totalSlots is the per-operating-point budget.  A later-point grant
% must extend the symbol ledger instead of being silently discarded.
dlSweep = dlSymbol;
dlSweep.Slot = 5;
dlSweep.TBSBits = NaN;
dlSweep.TBSize_bits = 280;
dlSweep.OfferedBits = 280;
dlSweep.GoodBits = 140;
cfgSweep = sixgr.util.structSet(cfgSymbol, "run.totalSlots", 2);
artifacts = sixgr.truth.exportLLSLiveDerivedTables(cfgSweep, tmp, ...
    struct("DL", dlSweep, "UL", table(), "SRS", table(), "TRS", table()), ...
    struct(), struct(), struct());
S = readtable(artifacts.SymbolThroughputPath, "VariableNamingRule", "preserve");
sweepRows = S(S.Slot == 5 & ismember(S.SymbolInSlot, [2; 3]), :);
assert(height(S) == 84 && height(sweepRows) == 2, ...
    "Absolute sweep slot 5 must extend the two-slot configured axis to six slots.");
assert(abs(sum(double(sweepRows.ScheduledDLBits)) - 280) < 1e-9 && ...
    abs(sum(double(sweepRows.GoodDLBits)) - 140) < 1e-9, ...
    "Symbol ledger must conserve the canonical raw TBSize_bits and GoodBits values.");

emptyCSISummary = table("DL", "csi_rs_runtime_trials", 20, ...
    "configured_operating_point_metadata", NaN, NaN, NaN, NaN, NaN, 0, "", ...
    'VariableNames', {'Direction','TraceSource','SNR_dB','SNR_dBValueRole', ...
    'MeanNMSE_dB','MeanWidebandCQI','MeanPMI','MeanCRI', ...
    'MeanCSIPayloadBitLength','SampleCount','Notes'});
emptyCSISummary = sixgr.truth.canonicalizeLLSLiveSignalChainTable("csirs_stats", emptyCSISummary);
assert(all(ismember(["MeanCRI","MeanCSIPayloadBitLength","SampleCount"], ...
    string(emptyCSISummary.Properties.VariableNames))), ...
    "Declared CSI-RS summary schema must retain CRI/payload/count columns even before measurements arrive.");

ok = true;
end
