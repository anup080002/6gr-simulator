function ok = testRAN1AI1032SLSCampaignCases()
%TESTRAN1AI1032SLSCAMPAIGNCASES Verify exact case axes and pairing.

setup6GRSimToolkit("Verbose", false);
cfg = sixgr.studies.ran1ai1032.loadStudyConfig();
out = sixgr.studies.ran1ai1032.buildSLSCampaignCases(cfg);
T = out.Cases;
assert(all(T.PlannedExecutionArchitecture=="calibrated_link_abstraction") && ...
    all(T.PlannedResultClassification=="calibrated_sls_estimate_not_waveform_truth"));
badCfg=cfg; badCfg.sls.execution.allow_truth_export=true;
localReject(@()sixgr.studies.ran1ai1032.validateStudyConfig(badCfg));
badCfg=cfg; badCfg.sls.execution.allow_uncalibrated_beta=true;
localReject(@()sixgr.studies.ran1ai1032.validateStudyConfig(badCfg));
badPlan=T; badPlan.PlannedResultClassification(1)="executed_phy_truth";
localReject(@()sixgr.studies.ran1ai1032.validateSLSCampaignCases(badPlan,cfg));

expectedBasePairs = 2 * 2 * 3 * 30;
expectedVariants = 2 * 2 * 2;
expectedCasePairs = expectedBasePairs * expectedVariants;
assert(out.Status == "PASS" && out.BasePairCount == expectedBasePairs && ...
    out.VariantCountPerComparator == expectedVariants && ...
    out.CasePairCount == expectedCasePairs && ...
    out.CaseCount == expectedCasePairs * 6, ...
    "The SLS case builder must cover every configured scenario/population/RU/drop/comparator/UE/spatial/power axis.");
assert(isequal(sort(unique(T.Scenario)), sort(["UMa";"UMi-Street-Canyon"])) && ...
    isequal(sort(unique(T.Population)), sort(["Profile-1";"Profile-3"])) && ...
    isequal(sort(unique(T.TargetRUPercent)), [20;50;70]) && ...
    isequal(sort(unique(T.UETxChains)), [2;4]) && ...
    isequal(sort(unique(T.UETxPower_dBm)), [31;35]), ...
    "The generated matrix must retain the exact configured SLS axes.");
assert(any(T.MUMIMOEnabled) && any(~T.MUMIMOEnabled) && ...
    all(T.MUMIMOEnabled == T.ULMUMIMOEnabled), ...
    "The matrix must contain MU-MIMO main and SU-MIMO-only ablation cases.");

s4 = T.ComparatorID == "S4";
s5 = T.ComparatorID == "S5";
assert(all(T.ComparatorMaxRank(s4) == 2) && ...
    all(T.ComparatorMaxRank(s5) == 4) && ...
    all(T.AdaptiveRank) && all(T.InitialRank == 1), ...
    "S4/S5 rank semantics and adaptive rank must remain explicit.");
assert(all(T.EffectiveMaxRank(T.UETxChains == 2) <= 2) && ...
    all(T.EffectiveMaxRank(s5 & T.UETxChains == 4) == 4) && ...
    all(T.PhysicalRankLimited == ...
        (T.ComparatorMaxRank > T.PhysicalMaxRank)), ...
    "Rank-4 may execute only with four physical UE transmit chains.");

pairRows = T.CasePairKey == T.CasePairKey(1);
assert(isequal(sort(T.ComparatorID(pairRows)), sort(["S0";"S1";"S2";"S3";"S4";"S5"])) && ...
    numel(unique(T.SeedBundleID(pairRows))) == 1 && ...
    numel(unique(T.ArrivalStreamID(pairRows))) == 1, ...
    "Every expanded pair must preserve S0--S5 and one frozen stochastic identity.");
delta = T.ConfigDelta{find(s5 & T.UETxChains == 4 & ...
    T.MUMIMOEnabled & T.UETxPower_dBm == 31, 1, "first")};
assert(delta.phy.pusch.maxLayers == 4 && ...
    delta.system.resourceReservations.enabled && ...
    delta.system.resourceReservations.commonChannelCalendarEnabled && ...
    startsWith(string(delta.system.linkAbstraction.requiredRFProfileID),"pn7_ptrs_compensated:") && ...
    delta.phy.pusch.numLayers == 1 && ...
    delta.mimo.ul_mu_mimo_enable && ...
    delta.scenario.ue.txPower_dBm == 31 && ...
    delta.scenario.layout.nSites == 7 && ...
    delta.scenario.layout.nSectorsPerSite == 3 && ...
    delta.scenario.layout.wraparound && ...
    string(delta.scenario.layout.wraparoundMode) == ...
        "hex_cluster_min_image" && ...
    isequal(size(delta.scenario.layout.wraparoundTranslationVectors_m), ...
        [2 2]) && ...
    delta.traffic.model == "ftp3" && ...
    delta.scenario.ue.nUE == 210, ...
    "Config delta must encode the executable rank, MIMO, power and 21-cell layout authority.");
runtimeParams = T.ExecutionParameters{find(pairRows, 1, "first")};
assert(runtimeParams.SeedBundle.GeometrySeed == T.GeometrySeed(find(pairRows, 1, "first")) && ...
    runtimeParams.SeedBundle.TrafficSeed == T.TrafficSeed(find(pairRows, 1, "first")) && ...
    runtimeParams.FWAPopulationSpec.ExpectedUECount == 210 && ...
    string(runtimeParams.FWAPopulationSpec.ProfileID) == ...
        T.Population(find(pairRows, 1, "first")), ...
    "Execution parameters must bind the paired component seeds consumed by SystemLevelRunner.");
assert(all(T.ExecutionStatus == ...
    "blocked_pending_lls_adaptive_calibration") && ...
    ~any(T.PrimaryResultEligible) && ...
    all(T.ExecutionBlocker == ...
    "missing_executed_phy_truth_fixed_mcs_calibration"), ...
    "Uncalibrated adaptive SLS cases must remain blocked and ineligible for primary results.");

tampered = T;
tampered.GeometrySeed(find(pairRows, 1, "last")) = ...
    tampered.GeometrySeed(find(pairRows, 1, "last")) + 1;
threw = false;
try
    sixgr.studies.ran1ai1032.validateSLSCampaignCases(tampered, cfg);
catch ME
    threw = ME.identifier == "sixgr:ran1ai1032:ExpandedPairSeedChanged";
end
assert(threw, "Changing one comparator seed must fail closed.");
ok = true;
fprintf('RAN1_AI1032_SLS_CAMPAIGN_CASES_PASS cases=%d\n',height(T));
end

function localReject(fun)
caught=false;
try, fun(); catch ME, caught=strcmp(ME.identifier,'sixgr:ran1ai1032:SLSArchitecture'); end
assert(caught,'Reject truth relabeling and uncalibrated SLS policy.');
end
