function ok = testNoSyntheticBLERFallbacks()
%TESTNOSYNTHETICBLERFALLBACKS Guard removed BLER LUT/DB/default behavior.

setup6GRSimToolkit("Verbose", false);
repoRoot = fileparts(which("setup6GRSimToolkit"));

assert(exist(fullfile(repoRoot, "+sixgr", "+system", "BLER_LUT.m"), "file") == 0, ...
    "BLER_LUT source must not be present in the active repo.");
assert(exist(fullfile(repoRoot, "+sixgr", "+system", "BLER_DB.m"), "file") == 0, ...
    "BLER_DB source must not be present in the active repo.");

campaignSource = string(fileread(fullfile(repoRoot, "sixgr_run_3gpp_full_campaign.m")));
for forbidden = [ ...
        "localEstimateHARQSuccessProb", ...
        "localEstimateHARQSuccessProbLogistic", ...
        "localFastLUTDelivery", ...
        "localBuildDualDirectionBLERLUTFromSweep", ...
        "localNormalizeBLERCurve", ...
        "fallback_logistic", ...
        "external_default_lut", ...
        "airRes.Mode = ""lut""", ...
        "model.Mode = ""logistic""", ...
        "structGet(opt, ""E2EAirModel"", ""lut"")", ...
        "structGet(airModel, ""Mode"", ""lut"")", ...
        "CalibrateSystemBLERFromLink"", true" ...
        ]
    assert(~contains(campaignSource, forbidden), ...
        "Campaign source still contains synthetic/default BLER behavior token: " + forbidden);
end

cfg = sixgr.config.defaultConfig();
for backend = ["bler_lut", "bler_db", "lut", "proxy", "abstract"]
    threw = false;
    try
        sixgr.system.PhyFactory.create(cfg, struct("PHYBackend", backend)); %#ok<NASGU>
    catch ME
        threw = strcmp(ME.identifier, "sixgr:system:ProxyBackendRemoved");
    end
    assert(threw, "PhyFactory must reject removed proxy backend: " + backend);
end

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

common = { ...
    "ResultsRoot", tmp, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", 0.02, ...
    "E2EMaxSlots", 24, ...
    "E2EUECount", 1, ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", false, ...
    "GenerateCampaignPlots", false ...
    };

for airModel = ["lut", "logistic"]
    threw = false;
    try
        sixgr_run_3gpp_full_campaign(cfg, common{:}, "E2EAirModel", airModel); %#ok<NASGU>
    catch ME
        threw = strcmp(ME.identifier, "sixgr:campaign:ProxyModeRemoved");
    end
    assert(threw, "Campaign runner must reject removed E2EAirModel=" + airModel);
end

threwCalibration = false;
try
    sixgr_run_3gpp_full_campaign(cfg, common{:}, ...
        "E2EAirModel", "truth", ...
        "CalibrateSystemBLERFromLink", true); %#ok<NASGU>
catch ME
    threwCalibration = strcmp(ME.identifier, "sixgr:campaign:ProxyModeRemoved");
end
assert(threwCalibration, "Campaign runner must reject synthetic BLER calibration export.");

ok = true;
end
