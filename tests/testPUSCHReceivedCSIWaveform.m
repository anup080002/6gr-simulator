function ok=testPUSCHReceivedCSIWaveform(outputRoot)
% OFDM/DM-RS/LDPC/CSI round trip on an explicitly authored AWGN component.
% This is not a fading, access, scheduler, or link-adaptation qualification.
setup6GRSimToolkit('Verbose',false);
if nargin<1, outputRoot=tempname(fullfile(pwd,'logs')); end
assert(~isfolder(outputRoot),'test:EvidenceExists','Preserve previous waveform evidence.');
mkdir(outputRoot);
prior=rng; cleanup=onCleanup(@()rng(prior)); %#ok<NASGU>
rng(3821208,'twister');
cfg=sixgr.config.defaultConfig();
cfg.channel.model="AWGN"; cfg.channel.awgnOnly=true;
cfg.phy.nTxAnt=1; cfg.phy.nRxAnt=1;
cfg.channel.nTxAnt=1; cfg.channel.nRxAnt=1;
cfg.scenario.ue.nTxAnt=1; cfg.antenna.ue.numElements=1;
cfg.phy.carrier.NSizeGrid=12; cfg.phy.carrier.SubcarrierSpacing=30;
cfg.phy.pusch.prbSet=0:5; cfg.phy.pusch.symbolAllocation=[0 14];
cfg.phy.pusch.modulation="QPSK"; cfg.phy.pusch.codeRate=.3;
cfg.phy.pusch.mcsIndex=4; cfg.phy.pusch.numLayers=1; cfg.phy.pusch.nLayers=1;
cfg.phy.pusch.numAntennaPorts=1; cfg.phy.pusch.numPorts=1;
cfg.phy.pusch.transmissionScheme="nonCodebook";
cfg.phy.pusch.transformPrecoding=false; cfg.phy.pusch.enablePTRS=false;
cfg.phy.pusch.equalizer="MMSE";
cfg.phy.pusch.dmrs.typeAPosition=2; cfg.phy.pusch.dmrs.configurationType=1;
cfg.phy.pusch.dmrs.additionalPosition=1; cfg.phy.pusch.dmrs.maxLength=1;
cfg.phy.pusch.dmrs.numCDMGroupsWithoutData=2;
cfg.phy.channelEstimation.method="LS";
request=struct('ReportConfigID',"received_csi_waveform_fixture",'Epoch',0, ...
    'CodebookType',"typeI-SinglePanel",'Ports',4,'Rank',2,'MaxRank',2, ...
    'N1',2,'N2',1,'O1',4,'O2',1,'CodebookMode',2, ...
    'ReportQuantity',"cri-RI-LI-PMI-CQI",'NumCSIResources',4, ...
    'FrequencyGranularity',"wideband",'UCIChannel',"PUSCH");
reportCfg=sixgr.phy.mimo.CSIReportConfiguration(request,0);
[~,values]=sixgr.phy.mimo.TypeISinglePanelCodebook.matrix(request,5);
values.RI=2; values.CRI=2; values.CQI_CW0=11; values.LI=1;
report=reportCfg.build(values);
payload=sixgr.phy.ul.pusch.PUSCHUCIPayload('HARQACK',int8([1;0]), ...
    'CSIPart1',report.Part1Bits,'CSIPart2',report.Part2Bits);
tx=sixgr.phy.ul.PUSCH_Tx(cfg,'UCIPayload',payload,'InitialIMCSPerCodeword',4);
% The DL CSI rank need not equal the number of layers on its UL transport.
request.Rank=1; cfg.phy.csi.reportConfiguration=request;
cfg.phy.csi.reportConfigurationEpoch=0;
poison=sixgr.phy.ul.pusch.PUSCHUCIPayload('HARQACK',int8([0;1]), ...
    'CSIPart1',1-report.Part1Bits,'CSIPart2',int8(1));
noiseVariance=1e-7;
received=tx.Waveform+sqrt(noiseVariance/2)*(randn(size(tx.Waveform))+1i*randn(size(tx.Waveform)));
for explicitLayout=[false true]
    args={};
    if explicitLayout, args={'CodingLayout',tx.CodingLayout}; end
    rx=sixgr.phy.ul.PUSCH_Rx(received,cfg,'Carrier',tx.Carrier,'PUSCH',tx.PUSCH, ...
        'TransportBlockSize',tx.TransportBlockSize,'TargetCodeRate',tx.TargetCodeRate, ...
        'RV',tx.RV,'ExpectedUCIPayload',poison,'InitialIMCSPerCodeword',4, ...
        'NoiseVar',noiseVariance,'NoiseVarDomain','time',args{:});
    assert(rx.Ok && ~rx.CRCError && isequal(rx.TransportBlock,tx.TransportBlock));
    assert(isequal(rx.DecodedHARQACKBits,payload.HARQACK) && ~rx.HARQACKContentMatch);
    assert(isequal(rx.DecodedCSIPart1Bits,report.Part1Bits) && ...
        isequal(rx.DecodedCSIPart2Bits,report.Part2Bits));
    assert(rx.CSI1BitCount==numel(report.Part1Bits) && rx.CSI2BitCount==numel(report.Part2Bits));
    e=rx.UCIReceiverEvidence;
    assert(e.CSIPart1DecodedBeforePart2 && ...
        e.CSI2LengthAuthority=="received_csi_part1_and_active_report_configuration");
    assert(e.ResolvedCSI2BitCount==rx.CSI2BitCount);
    assert(rx.CodingLayout.RateMatchedBitCount==tx.CodingLayout.RateMatchedBitCount);
    assert(~rx.CSI1ContentMatch && ~rx.CSI2ContentMatch);
    assert(~e.CSI1.CRCApplicable && isnan(e.CSI1.CRCPass));

    % Independently declared receive obligation: never derive its HARQ width
    % from payload.HARQACK or the UE report. This component does not claim a
    % real gNB schedule/capture binding; that belongs to the shared runtime.
    obligation=struct('ObservationID',"declared_pusch_waveform_capture", ...
        'ConfigurationEpoch',0,'AssignmentDigest',"declared_ul_assignment", ...
        'HARQMappingDigest',"declared_two_assignment_mapping", ...
        'HARQACKBitCount',2,'ConfiguredGrantUCIBitCount',0, ...
        'CSIReportConfigID',"received_csi_waveform_fixture",'CSIConfigurationEpoch',0);
    context=sixgr.phy.ul.pusch.PUSCHUCIReceiveContext(obligation);
    installed=sixgr.phy.mimo.CSIReportConfiguration(request,0);
    % A contradictory TX-side/config report cannot determine receiver sizing.
    rxCfg=cfg;
    rxCfg.phy.pusch.ExpectedUCIPayload=poison;
    rxCfg.phy.pusch.uciPayload=poison;
    rxCfg.phy.csi.reportConfiguration=struct('Rank',NaN,'TXPart2BitCount',999);
    independent=sixgr.phy.ul.PUSCH_Rx(received,rxCfg, ...
        'Carrier',tx.Carrier,'PUSCH',tx.PUSCH, ...
        'TransportBlockSize',tx.TransportBlockSize,'TargetCodeRate',tx.TargetCodeRate, ...
        'RV',tx.RV,'UCIReceiveContext',context,'UCIReportConfiguration',installed, ...
        'InitialIMCSPerCodeword',4,'NoiseVar',noiseVariance,'NoiseVarDomain','time',args{:});
    assert(independent.Ok && ~independent.CRCError && ...
        isequal(independent.TransportBlock,tx.TransportBlock));
    assert(independent.CSIPresenceResolved && independent.CSIReportDetected && ...
        independent.CSIPresenceEvidence.SelectedCandidate==2 && ...
        isequal(independent.CSIPresenceEvidence.CandidateTBCRCPass,[0;1]));
    normalized=sixgr.truth.normalizeReceivedPUSCHCSI(independent,context,installed);
    assert(normalized.DecodeOk && normalized.Fields.RI==2 && normalized.Fields.CQI_CW0==11 && ...
        isequal(normalized.DecodedPart1,report.Part1Bits) && isequal(normalized.DecodedPart2,report.Part2Bits));
    poisoned=independent;
    poisoned.ExpectedCSIPart1Bits=ones(99,1); poisoned.ExpectedCSIPart2Bits=NaN;
    poisoned.GrantSnapshot=struct('UCIOnPUSCHCSIReportIdentity',"wrong_TX_report");
    assert(isequaln(normalized,sixgr.truth.normalizeReceivedPUSCHCSI(poisoned,context,installed)));
    for badBits={NaN,Inf,.5,[1 2],complex(1,1)}
        bad=independent; bad.DecodedCSIPart1Bits=badBits{1};
        localReject(@()sixgr.truth.normalizeReceivedPUSCHCSI(bad,context,installed), ...
            'sixgr:truth:InvalidReceivedCSIBit');
    end
    bad=independent; bad.UCIReceiverEvidence.ReceiverContextDigest="wrong_context";
    localReject(@()sixgr.truth.normalizeReceivedPUSCHCSI(bad,context,installed), ...
        'sixgr:truth:PUSCHCSIReceiveContextMismatch');
    assert(~independent.CSIPresenceEvidence.PriorHARQSoftBufferUsed && ...
        ~independent.CSIPresenceEvidence.TransmitterMetadataUsed);
    assert(isequal(independent.DecodedHARQACKBits,payload.HARQACK) && ...
        isequal(independent.DecodedCSIPart1Bits,report.Part1Bits) && ...
        isequal(independent.DecodedCSIPart2Bits,report.Part2Bits));
    assert(independent.HARQACKBitCount==2 && ...
        independent.CSI2BitCount==numel(report.Part2Bits));
    assert(~independent.UCIReferenceScoringAvailable && ...
        independent.UCIReceiveContextDigest==context.Digest);
    assert(~any(isfield(independent,{'ExpectedHARQACKBits','ExpectedCSIPart1Bits', ...
        'ExpectedCSIPart2Bits','ExpectedConfiguredGrantUCIBits', ...
        'HARQACKContentMatch','CSI1ContentMatch','CSI2ContentMatch', ...
        'ConfiguredGrantUCIContentMatch'})), ...
        'A receiver without a TX reference must not fabricate scoring fields.');
    assert(string(independent.HARQACKDecodeStatus)=="decoded_usable" && ...
        independent.UCIReceiverEvidence.HARQACK.DecodeUsable && ...
        independent.UCIReceiverEvidence.HARQMappingDigest==obligation.HARQMappingDigest);
    assert(isequal(independent.CodingLayout,rx.CodingLayout) && ...
        isequal(independent.ULSCHCodewordLLR,rx.ULSCHCodewordLLR), ...
        'The receiver-owned UCI boundary must retain identical received UL-SCH resources.');
    localReject(@()sixgr.phy.ul.PUSCH_Rx(received,cfg, ...
        'UCIReceiveContext',context,'ExpectedUCIPayload',poison), ...
        'sixgr:pusch:ConflictingUCIReceiveAuthority');
    localReject(@()sixgr.phy.ul.PUSCH_Rx(received,cfg, ...
        'UCIReportConfiguration',installed), 'sixgr:pusch:MissingUCIReceiveContext');
    localReject(@()sixgr.phy.ul.PUSCH_Rx(received,cfg, ...
        'UCIReceiveContext',context,'UCIReportConfiguration',installed), ...
        'sixgr:pusch:MissingUCIReceiveCodingAuthority');
    localReject(@()sixgr.phy.ul.PUSCH_Rx(received,cfg, ...
        'UCIReceiveContext',context,'UCIReportConfiguration',installed, ...
        'TransportBlockSize',tx.TransportBlockSize,'TargetCodeRate',tx.TargetCodeRate, ...
        'RV',tx.RV), 'sixgr:pusch:MissingUCIReceiveCodingAuthority');
end
save(fullfile(outputRoot,'csi_present_waveform.mat'),'cfg','context','installed', ...
    'tx','received','independent','noiseVariance');
% Same installed gNB CSI occasion, but the UE sends only HARQ + UL-SCH.
% Presence is selected from this actual waveform's TB CRC, not this fixture's
% knowledge that the payload omitted CSI. Wrong cfg/TX metadata stays poisoned.
absentPayload=sixgr.phy.ul.pusch.PUSCHUCIPayload('HARQACK',int8([1;0]));
absentTx=sixgr.phy.ul.PUSCH_Tx(cfg,'UCIPayload',absentPayload,'InitialIMCSPerCodeword',4);
absentWaveform=absentTx.Waveform+sqrt(noiseVariance/2)* ...
    (randn(size(absentTx.Waveform))+1i*randn(size(absentTx.Waveform)));
absentRx=sixgr.phy.ul.PUSCH_Rx(absentWaveform,rxCfg, ...
    'Carrier',absentTx.Carrier,'PUSCH',absentTx.PUSCH, ...
    'TransportBlockSize',absentTx.TransportBlockSize,'TargetCodeRate',absentTx.TargetCodeRate, ...
    'RV',absentTx.RV,'UCIReceiveContext',context,'UCIReportConfiguration',installed, ...
    'InitialIMCSPerCodeword',4,'NoiseVar',noiseVariance,'NoiseVarDomain','time');
save(fullfile(outputRoot,'csi_absent_waveform.mat'),'rxCfg','context','installed', ...
    'absentTx','absentWaveform','absentRx','noiseVariance');
assert(absentRx.Ok && ~absentRx.CRCError && ...
    isequal(absentRx.TransportBlock,absentTx.TransportBlock));
assert(absentRx.CSIPresenceResolved && ~absentRx.CSIReportDetected && ...
    absentRx.CSIPresenceEvidence.SelectedCandidate==1 && ...
    absentRx.CSIPresenceEvidence.CandidateTBCRCPass(1)==1 && ...
    absentRx.CSIPresenceEvidence.CandidateTBCRCPass(2)~=1);
assert(isequal(absentRx.DecodedHARQACKBits,absentPayload.HARQACK) && ...
    absentRx.UCIReceiverEvidence.HARQACK.DecodeUsable);
assert(absentRx.CSI1BitCount==0 && absentRx.CSI2BitCount==0 && ...
    isempty(absentRx.DecodedCSIPart1Bits) && isempty(absentRx.DecodedCSIPart2Bits));
[usable,crc]=sixgr.truth.puschCSIReceiverUsable(absentRx, ...
    absentRx.DecodedCSIPart1Bits,absentRx.DecodedCSIPart2Bits,[0 0]);
assert(~usable && isnan(crc),'A correctly received absent-CSI interpretation cannot publish CSI.');
normalizedAbsent=sixgr.truth.normalizeReceivedPUSCHCSI(absentRx,context,installed);
assert(~normalizedAbsent.DecodeOk && isnan(normalizedAbsent.CRCPass) && isempty(fieldnames(normalizedAbsent.Fields)));
% Actual OFDM negative fixture: spare CRI must not erase independent HARQ.
% This intentionally invalid UCI is a test stimulus, not a valid CSI report
% or an injected runtime measurement. The existing valid-waveform checks above
% remain unchanged. Variable Part-2 sizes leave this codeword's data unresolved.
request.ReportQuantity="cri-RI-LI-PMI-CQI";
request.NumCSIResources=3; request.Rank=2;
invalidSchema=sixgr.phy.mimo.CSIReportConfiguration(request,0);
% Keep mode-2 four-port geometry. PMI alone has six bits at either rank;
% LI adds zero/one bits, so received RI is genuinely needed for Part 2.
assert(isequal(invalidSchema.part2BitCountCandidates(),[6 7]), ...
    'The partial-waveform fixture must have different configured Part-2 lengths.');
[~,invalidValues]=sixgr.phy.mimo.TypeISinglePanelCodebook.matrix(request,0);
invalidValues.RI=2; invalidValues.CRI=2; invalidValues.CQI_CW0=9;
invalidValues.LI=1;
validReport=invalidSchema.build(invalidValues);
badPart1=validReport.Part1Bits;
assert(invalidSchema.Part1Fields(1)=="CRI" && invalidSchema.Part1Widths(1)==2);
badPart1(1:2)=int8([1;1]);
badPayload=sixgr.phy.ul.pusch.PUSCHUCIPayload('HARQACK',int8([1;0;1;0;1]), ...
    'CSIPart1',badPart1,'CSIPart2',validReport.Part2Bits);
invalidTx=sixgr.phy.ul.PUSCH_Tx(cfg,'UCIPayload',badPayload,'InitialIMCSPerCodeword',4);
badWaveform=invalidTx.Waveform+sqrt(noiseVariance/2)* ...
    (randn(size(invalidTx.Waveform))+1i*randn(size(invalidTx.Waveform)));
obligation.HARQACKBitCount=5; obligation.HARQMappingDigest="declared_five_assignment_mapping";
context=sixgr.phy.ul.pusch.PUSCHUCIReceiveContext(obligation);
partial=sixgr.phy.ul.PUSCH_Rx(badWaveform,cfg, ...
    'Carrier',invalidTx.Carrier,'PUSCH',invalidTx.PUSCH, ...
    'TransportBlockSize',invalidTx.TransportBlockSize,'TargetCodeRate',invalidTx.TargetCodeRate, ...
    'RV',invalidTx.RV,'UCIReceiveContext',context,'UCIReportConfiguration',invalidSchema, ...
    'InitialIMCSPerCodeword',4,'NoiseVar',noiseVariance,'NoiseVarDomain','time');
assert(partial.UCIOnPUSCH.PartialReception && ~partial.UCIOnPUSCH.CSIPart1Usable);
assert(partial.UCIOnPUSCH.CSIRejectionIdentifier=="sixgr:mimo:InvalidCRI");
assert(isequal(partial.DecodedHARQACKBits,badPayload.HARQACK));
assert(partial.UCIReceiverEvidence.HARQACK.DecodeUsable);
assert(partial.UCIOnPUSCHApplied && partial.HARQACKBitCount==5 && ...
    string(partial.HARQACKDecodeStatus)=="decoded_usable");
assert(sixgr.truth.puschUCIFieldUsable(partial.UCIReceiverEvidence.HARQACK, ...
    partial.DecodedHARQACKBits,partial.HARQACKBitCount));
assert(partial.PartialReception && ~partial.CSIPart1Usable && isnan(partial.CSI2BitCount));
assert(partial.ChannelEstimateAttempted && partial.ChannelEstimateAvailable && ...
    partial.ResourceExtractionAvailable && partial.EqualizationAttempted && partial.EqualizationAvailable);
assert(isequaln(partial.ReceiverHestSINR_dB,partial.ReceiverSINR.Value) && ...
    string(partial.ReceiverHestSINRValueStatus)==string(partial.ReceiverSINR.ValueStatus));
assert(isequaln(partial.PreEqualizationNoiseVariance,partial.NoiseVar) && ...
    partial.PreEqualizationNoiseVarianceDomain=="resource_grid_pre_equalization");
assert(~isempty(partial.QAMEqualizedSymbolsForEvidence) && ...
    partial.QAMEqualizedSymbolDomain=="layer");
assert(~partial.ULSCHDecodeAttempted && ~partial.ULSCHDecodeAvailable && ~partial.LLRAvailable);
assert(~partial.StrictReceiverEvidenceOk && ~partial.StrictOk && ...
    partial.TruthStatus=="partial_receiver_evidence");
assert(contains(string(partial.SINRValidationReason),"ulsch_decode_not_attempted") && ...
    ~contains(string(partial.FailureReason),"tb_crc_failed"));
assert(~partial.Ok && ~partial.DecodeAttempted && ~any(partial.TransportBlockDecodeAttempted));
assert(~all(partial.ULSCHMappingResolved) && isempty(partial.TransportBlock));
assert(~any(isfield(partial,{'CRCError','CRCPass','TBCRCPass','HARQACKContentMatch'})), ...
    'Unattempted transport-block CRC and unavailable TX scoring must not be fabricated.');
ok=true; fprintf('PUSCH_RECEIVED_CSI_WAVEFORM_PASS: valid layout contracts and invalid-CSI independent HARQ.\n');
end

function localReject(fn,id)
try
    fn();
catch ME
    assert(strcmp(ME.identifier,id),'Expected %s, got %s: %s',id,ME.identifier,ME.message);
    return;
end
error('test:MissingRejection','Expected %s.',id);
end
