function grant = localFinalizeSchedulerTruthGrant(cfg, seedGrant, direction)
direction = upper(string(direction));
grant = seedGrant;
grant.Direction = char(direction);
nPRB = double(sixgr.util.structGet(cfg, "frequency.n_size_grid", 24));
nPRB = max(1, round(nPRB));
grant.PRBSet = 0:(nPRB - 1);
root = "phy.pdsch";
if direction == "UL"
    root = "phy.pusch";
end
grant.SymbolAllocation = double(sixgr.util.structGet( ...
    cfg, root + ".SymbolAllocation", [0 14]));
grant.NumLayers = double(sixgr.util.structGet( ...
    cfg, root + ".nLayers", 1));
grant.Layers = grant.NumLayers;
grant.DMRSPortSet = 0:(grant.NumLayers - 1);
[grant.PTRSEnabled, grant.PTRSPortSet, grant.PTRSPortSetSource] = ...
    sixgr.phy.grant.resolveScheduledPTRSPortSet( ...
    cfg, direction, grant.DMRSPortSet, grant);
[modulation, targetCodeRate, mcsIndex] = sixgr.link.amcFromCQI( ...
    double(grant.CQIUsed), "", NaN, cfg, direction);
grant.Modulation = char(string(modulation));
grant.TargetCodeRate = double(targetCodeRate);
grant.MCSIndex = double(mcsIndex);
grant.MCS = double(mcsIndex);
if direction == "DL"
    grant.MCSContext = sixgr.util.structGet( ...
        cfg, "phy.pdsch.mcsContext", struct());
end
scheduler = sixgr.l2.mac.SchedulerPF(cfg, "Direction", direction);
grant = scheduler.finalizeExactPHYFeasibility(grant);
assert(logical(grant.ExactPHYFeasible) && double(grant.TBSBits) > 0, ...
    "%s raw-trial fixture requires a production exactly feasible grant: %s", ...
    direction, string(sixgr.util.structGet(grant, ...
        "ExactPHYInfeasibilityReason", "unknown")));
grant.DCI = struct("BitExactPDCCHPayload", true);
bindingHash = "raw-trial-provenance-" + lower(direction) + "-binding";
grant.ControlDecodeOk = true;
grant.PDCCHGrantBindingRequired = true;
grant.PDCCHGrantBindingOk = true;
grant.PDCCHGrantDCIId = "raw-trial-provenance-" + lower(direction) + "-dci";
grant.PDCCHGrantDCIFieldsHash = char(bindingHash);
grant.PDCCHGrantFieldsHash = char(bindingHash);
grant.PHYGrant = sixgr.phy.grant.freezePHYGrant(cfg, direction, grant, ...
    "SNR_dB", 10, "Frame", grant.Frame, "Slot", grant.Slot);
end

