function ok = testReleaseNumericalAcceptanceSuite()
%TESTRELEASENUMERICALACCEPTANCESUITE Layered 10/10 numerical release gate.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

anchors = { ...
    "core_release_baseline_spec", @() core.releaseBaselineSpecAcceptance(); ...
    "core_pure_math", @() core.pureMathAcceptance(); ...
    "phy_grid_bit_waveform", @() phy.gridBitWaveformAcceptance(); ...
    "channel_calibration", @() channel.calibratedChannelAcceptance(); ...
    "link_interference_campaign", @() link.interferenceCampaignAcceptance(); ...
    "mac_harq_control_access", @() mac.harqControlAcceptance(); ...
    "core_kpi_reproducibility", @() core.kpiReproducibilityAcceptance(); ...
    "core_release_matrix", @() core.releaseScenarioMatrixAcceptance() };

rows = repmat(struct("Anchor", "", "Elapsed_s", NaN), size(anchors, 1), 1);
for i = 1:size(anchors, 1)
    t = tic;
    anchorOk = anchors{i, 2}();
    rows(i).Anchor = anchors{i, 1};
    rows(i).Elapsed_s = toc(t);
    assert(logical(anchorOk), "Release acceptance anchor '%s' returned false.", anchors{i, 1});
end

T = struct2table(rows);
assert(height(T) == size(anchors, 1) && all(isfinite(double(T.Elapsed_s))), ...
    "Release acceptance suite must record deterministic elapsed time for every anchor.");
fprintf("ReleaseNumericalAcceptanceSuite: anchors=%d maxAnchorElapsed_s=%.3f\n", ...
    height(T), max(double(T.Elapsed_s)));
ok = true;
end
