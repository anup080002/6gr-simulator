function ok=testReferenceMeasurementSINRProvenance()
% Labelled multi-plane publisher fixtures, not PHY qualification results.
row=struct('SINR_dB',12,'SINRSource',"selected_spatial_objective", ...
    'SINRValueRole',"scheduler_input",'SINRValueStatus',"OK", ...
    'SINRValueDefinition',"selected_rank_and_PMI_objective", ...
    'SINRMeasurementDomain',"selected_precoder_layers", ...
    'MeasuredTrialSINR_dB',20,'MeasuredTrialSINRSource',"reference_only", ...
    'ReferenceMeasuredSINR_dB',20,'ReferenceMeasuredSINRSource',"port3000_power_ratio", ...
    'ReferenceMeasuredSINRStatus',"available",'ReferenceMeasuredSINRDomain',"reference_RE", ...
    'ChannelEstimateDiagnosticSINR_dB',18,'ChannelEstimateDiagnosticSINRSource',"Hest_diagnostic");
state=struct('CurrentSlot',7);
state=sixgr.truth.CoupledTruthRuntime.publishReferenceSignalMeasurementRuntime( ...
    state,'CSI-RS','UE',1,row,'ProducerSlot',6,'AvailableSlot',7,'Valid',true);
T=state.ReferenceSignalMeasurementTable;
assert(T.SINR_dB==12 && T.SINRSourceField=="SINR_dB" && T.SINRSource==row.SINRSource);
assert(T.SINRMeasurementDomain==row.SINRMeasurementDomain && ...
    T.SINRValueDefinition==row.SINRValueDefinition && T.SINRValueRole=="scheduler_input");
assert(T.ReferenceMeasuredSINR_dB==20 && T.ReferenceMeasuredSINRSource=="port3000_power_ratio" && ...
    T.ReferenceMeasuredSINRDomain=="reference_RE" && T.ChannelEstimateDiagnosticSINR_dB==18);
assert(T.SINRProvenanceStatus=="source_and_measurement_domain_retained");
% Preserve contradiction for audit, not a replacement "available" label.
row.SINRValueStatus="unavailable_unqualified_domain";
state=sixgr.truth.CoupledTruthRuntime.publishReferenceSignalMeasurementRuntime( ...
    state,'CSI-RS','UE',1,row,'ProducerSlot',26,'AvailableSlot',27,'Valid',false);
assert(state.ReferenceSignalMeasurementTable.SINRValueStatus(end)==row.SINRValueStatus && ...
    ~state.ReferenceSignalMeasurementTable.Valid(end));
% A different selected alias must use that alias's own source/status/role.
row=struct('MeasuredTrialSINR_dB',7,'MeasuredTrialSINRSource',"SRS_pilot_receiver", ...
    'MeasuredTrialSINRValueRole',"received_pilot_measurement", ...
    'MeasuredTrialSINRValueStatus',"OK",'SINRMeasurementDomain',"SRS_pilot_RE", ...
    'SINRSource',"unrelated_should_not_leak");
state=sixgr.truth.CoupledTruthRuntime.publishReferenceSignalMeasurementRuntime( ...
    state,'SRS','UE',1,row,'ProducerSlot',45,'AvailableSlot',46,'Valid',true);
T=state.ReferenceSignalMeasurementTable(end,:);
assert(T.SINR_dB==7 && T.SINRSource=="SRS_pilot_receiver" && ...
    T.SINRMeasurementDomain=="SRS_pilot_RE" && T.SINRValueRole=="received_pilot_measurement");
assert(isnan(T.ReferenceMeasuredSINR_dB),'No CSI reference value may leak to another measurement row.');
ok=true; fprintf('REFERENCE_MEASUREMENT_SINR_PROVENANCE_PASS\n');
end
