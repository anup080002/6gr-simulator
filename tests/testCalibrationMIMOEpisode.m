function ok=testCalibrationMIMOEpisode()
% Both real coded directions must emit the YAML-declared per-layer feature.
[campaign,cases]=sixgr.calibration.loadCampaign( ...
    'configs/calibration/nr_dl_ul_rank2_feature_smoke.yaml');
assert(numel(cases)==2 && ...
    string(campaign.sinr_feature)== ...
    "applied_channel_per_data_re_per_layer_lmmse_not_receiver_measurement");
for k=1:numel(cases)
    cfg=cases(k).Config;
    cfg.simulation.snrDb=25;
    cfg=sixgr.lls.validateConfig(cfg);
    invalid=cfg;
    invalid.channel.rxAntennas=1;
    try
        sixgr.lls.validateConfig(invalid);
        error('test:MissingAWGNDimensionRejection', ...
            'Rectangular identity AWGN must be rejected.');
    catch ME
        assert(strcmp(ME.identifier,'sixgr:lls:AWGNIdentityDimensions'), ...
            'Expected AWGN dimension rejection; got %s: %s', ...
            ME.identifier,ME.message);
    end
    episode=sixgr.calibration.executeEpisode(cfg,25,0, ...
        [10261+10*k 10262+10*k 10263+10*k], ...
        "rank2_awgn_feature_test_"+string(k));
    assert(numel(episode.Attempts)==1 && ...
        episode.RawTrials{1}.NumLayers==2 && ...
        episode.RawTrials{1}.NumTxPorts==2 && ...
        episode.RawTrials{1}.NumRxAntennas==2);
    a=episode.Attempts(1);
    assert(size(a.SINRLinear,2)==2 && ...
        numel(a.SINRLinear)==a.DataRECount && ...
        all(isfinite(a.SINRLinear),'all') && ...
        all(a.SINRLinear>=0,'all') && ...
        a.WaveformExecuted && ...
        a.SINRSource== ...
            "applied_channel_per_data_re_per_layer_lmmse_not_receiver_measurement");
end
ok=true; fprintf('CALIBRATION_MIMO_EPISODE_PASS\n');
end
