function ok = testPDSCHSISORegression()
%TESTPDSCHSISOREGRESSION Keep the 1x1 PDSCH path on the legacy fast map.

setup6GRSimToolkit("Verbose", false);
if ~localHaveRequired5G()
    error("sixgr:test:Required5GToolboxUnavailable", ...
        ["testPDSCHSISORegression requires the 5G Toolbox APIs " ...
        "checked by localHaveRequired5G; unavailable tests cannot pass."]);
end

cfg = sixgr.config.defaultConfig();
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.run.pdschExecutionProfile = "phy_calibration";
cfg.phy.carrier.NSizeGrid = 12;
cfg.phy.pdsch.prbSet = 0:5;
cfg.phy.pdsch.symbolAllocation = [0 10];
cfg.phy.pdsch.modulation = 'QPSK';
cfg.phy.pdsch.codeRate = 0.3;
cfg.phy.pdsch.mcsTable = "calibration_explicit";
cfg.phy.pdsch.mcsIndex = 0;
cfg.phy.pdsch.mcsContext = struct( ...
    "UECapability1024QAM", false, ...
    "RRCEnabled1024QAM", false, ...
    "DCIEnabled1024QAM", false, ...
    "DeploymentAllows1024QAM", false, ...
    "FrequencyRange", "FR1", ...
    "OperatingBand", "n78", ...
    "DeploymentClass", "controlled_test", ...
    "FrequencyRangeAllows1024QAM", false, ...
    "BandAllows1024QAM", false);
cfg.phy.pdsch.nLayers = 1;
cfg.phy.pdsch.numLayers = 1;
cfg.phy.pdsch.enablePTRS = false;
cfg.phy.csirs.enable = false;

[tx, txInfo] = sixgr.phy.dl.PDSCH_Tx(cfg);
portContract = txInfo.ResourceGridPortContract;
assert(~logical(txInfo.Precoding.Active), "SISO path must bypass explicit precoding.");
assert(string(txInfo.Precoding.Mode) == "siso-bypass", "Unexpected SISO precoding mode.");
assert(size(tx.Grid, 3) >= 1, "SISO grid must expose at least one transmit page.");
assert(size(tx.PDSCHAntennaIndices, 2) == 1, "SISO PDSCH mapping must remain single-port.");
assert(size(tx.DMRSAntennaIndices, 2) == 1, "SISO DM-RS mapping must remain single-port.");
assert(portContract.PDSCHAntennaPortCount == 1 && portContract.DMRSAntennaPortCount == 1, ...
    "Port contract must preserve truthful single-port PDSCH and DM-RS mapping.");
assert(~logical(portContract.ResourceSelectiveChannelEstimateRequired), ...
    "Single-port DL mapping must not require resource-selective estimation by signal geometry alone.");
assert(logical(portContract.ScalarOrUnitShortcutEligibleBySignalGeometry), ...
    "Single-port DL mapping should remain scalar-shortcut eligible by signal geometry.");

txDataSym = nrPDSCH(tx.Carrier, tx.PDSCH, {tx.Codeword});
gridDataSym = tx.Grid(tx.PDSCHIndices);
assert(max(abs(gridDataSym(:) - txDataSym(:))) < 1e-10, ...
    "SISO PDSCH symbols no longer map directly to the resource grid.");

baseRXArgs = { ...
    "Carrier", tx.Carrier, ...
    "PDSCH", tx.PDSCH, ...
    "PDSCHIndices", tx.PDSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV};
localAssertIdentifier(@() sixgr.phy.dl.PDSCH_Rx( ...
    tx.Waveform, cfg, baseRXArgs{:}), ...
    "sixgr:pdsch:CalibrationReceiverMissingCodingPlan");
localAssertIdentifier(@() sixgr.phy.dl.PDSCH_Rx( ...
    tx.Waveform, cfg, ...
    "Carrier", tx.Carrier, ...
    "PDSCH", tx.PDSCH, ...
    "PDSCHIndices", tx.PDSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", mod(double(tx.RV) + 1,4), ...
    "CodingPlan", tx.CodingPlans), ...
    "sixgr:pdsch:CalibrationCodingPlanRVMismatch");

rx = sixgr.phy.dl.PDSCH_Rx(tx.Waveform, cfg, ...
    baseRXArgs{:}, ...
    "CodingPlan", tx.CodingPlans);

assert(rx.Ok, "SISO PDSCH round-trip must decode successfully.");
assert(isequal(int8(rx.TransportBlock(:)), int8(tx.TransportBlock(:))), ...
    "SISO PDSCH round-trip changed the recovered transport block.");
assert(string(rx.CodingPlans{1}.PlanID) == ...
        string(tx.CodingPlans{1}.PlanID) ...
        && string(rx.CodingPlans{1}.CodingLayoutHash) == ...
        string(tx.CodingPlans{1}.CodingLayoutHash), ...
    "Calibration TX/RX must consume the same immutable coding-plan identity.");
coding = sixgr.link.deriveCodingTrialMetrics(tx, txInfo, rx, cfg);
assert(coding.CodeBlockCount == 1 && coding.CodeBlockErrors == 0 && coding.CodeBlockBLER == 0, ...
    "Single-code-block PDSCH must not count TS 38.212 filler bits as code-block errors.");
assert(rx.MeasuredCodeBlockCRCCount == 0 && ~isfinite(rx.MeasuredCodeBlockCRCFailureRate), ...
    "Single-code-block PDSCH must leave CB-CRC failure rate undefined because no CRC24B exists.");
assert(rx.MeasuredCodeBlockDecodeCount == 1 && rx.MeasuredCodeBlockDecodeErrorCount == 0, ...
    "Single-code-block PDSCH must expose the measured decoded-code-block outcome.");
assert(rx.MeasuredCodeBlockDecodeFailureRate == 0 && string(rx.MeasuredCodeBlockDecodeErrorVector) == "[0]", ...
    "Single-code-block PDSCH must report decode outcome from the measured TB CRC result.");
ok = true;
end

function localAssertIdentifier(fn,identifier)
try
    fn();
catch cause
    assert(string(cause.identifier) == string(identifier), ...
        "Observed %s, expected %s.",cause.identifier,identifier);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.",identifier);
end

function tf = localHaveRequired5G()
tf = exist("nrPDSCH", "file") == 2 ...
    && exist("nrPDSCHDecode", "file") == 2 ...
    && exist("nrPDSCHPrecode", "file") == 2 ...
    && exist("nrChannelEstimate", "file") == 2;
end
