function ok = testRuntimeOperatingAuthority()
%TESTRUNTIMEOPERATINGAUTHORITY Canonical configured PHY authority is fail-closed.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "master_geometry_based.yaml");
scenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scenario, ...
    fullfile(tempdir, "sixgr_runtime_operating_authority_test"));

assert(cfg.runtime.phy.dl.NumLayers == 2 && cfg.runtime.phy.ul.NumLayers == 2);
assert(cfg.runtime.phy.dl.MCSIndex == 20 && cfg.runtime.phy.ul.MCSIndex == 20);
assert(cfg.runtime.link_adaptation.InitialMCSIndex == 0 && ...
    cfg.runtime.link_adaptation.MaximumMCSIndex == 20);
assert(strcmpi(string(cfg.runtime.phy.dl.Modulation), "256QAM") && ...
    strcmpi(string(cfg.runtime.phy.ul.Modulation), "256QAM"));
assert(isfinite(cfg.runtime.phy.dl.XOverhead) && ...
    isfinite(cfg.runtime.phy.ul.XOverhead), ...
    "Configured resource overhead must be part of immutable PHY authority.");
assert(cfg.runtime.antenna.gnb.NumPhysicalElements == 64 && ...
    cfg.runtime.antenna.ue.NumPhysicalElements == 4);
assert(cfg.runtime.antenna.gnb.NumTxRFChains == 4 && ...
    cfg.runtime.antenna.ue.NumTxRFChains == 2, ...
    "Directional YAML RF-chain capacity must survive runtime translation.");
assert(logical(cfg.runtime.features.ptrs.Enabled) && ...
    logical(cfg.runtime.features.srs.Enabled) && ...
    logical(cfg.runtime.features.csi_rs.Enabled) && ...
    logical(cfg.runtime.features.trs.Enabled) && ...
    logical(cfg.runtime.features.pucch.Enabled) && ...
    logical(cfg.runtime.features.prach.Enabled) && ...
    logical(cfg.runtime.features.mu_mimo.Enabled) && ...
    ~logical(cfg.runtime.features.ul_mu_mimo.Enabled), ...
    "Enabled YAML features must be present in the immutable runtime authority.");
assert(string(cfg.mac.scheduler.muMimoHybridRFDesignPolicy) == ...
    "measured_srs_phase_only_subarray" && ...
    string(cfg.phy.mimo.muMimoHybridRFDesignPolicy) == ...
    "measured_srs_phase_only_subarray", ...
    "Canonical-control MU hybrid RF policy must survive alias normalization into both runtime consumers.");
assert(strcmpi(string(cfg.phy.csi.acquisitionMode), "dl_based") && ...
    strcmpi(string(cfg.phy.csi.operationOrientation), "tdd_reciprocity") && ...
    strcmpi(string(cfg.reference_signals.csi_acquisition_mode), "dl_based") && ...
    strcmpi(string(cfg.reference_signals.operation_orientation), "tdd_reciprocity"), ...
    ["Canonical TDD/DL-CSI policy must reach the runtime while UL SRS " ...
     "remains an independently configured reciprocity measurement."]);
assert(strcmpi(string(scenario.get( ...
    "antenna_and_array.reciprocity_assumption", "")), ...
    "tdd_reciprocity"), ...
    "The operator YAML must align the base-array reciprocity assumption with the TDD CSI policy.");
assert(logical(sixgr.util.structGet(cfg, ...
    "validation.channel_rf_configured_vs_applied.enabled", false)), ...
    "A fading WebGUI run must enable strict waveform-backed Channel/RF evidence for path-angle materialization.");
assert(~logical(cfg.phy.csi.jointDLULCSIEnabled) && ...
    strcmpi(string(cfg.phy.csi.jointPortMappingPolicy), "disabled") && ...
    strcmpi(string(cfg.phy.csi.jointTimelinePolicy), "disabled"), ...
    "The master must not claim joint CSI without an explicit joint port map and causal timeline.");
assert(strlength(string(cfg.runtime.OperatingAuthoritySHA256)) == 64);
assert(istable(cfg.runtime.ParameterProvenanceTable) && ...
    height(cfg.runtime.ParameterProvenanceTable) >= 40);
requiredFeatures = ["scheduled_pdsch","scheduled_pusch", ...
    "ssb","pbch","pdcch","pdcch_blind_search","pdcch_dmrs","pucch", ...
    "prach","sib1","ptrs","csi_rs","srs","trs","tracking_rs", ...
    "ptrs_cpe_correction","reference_sweep","harq_diagnostics", ...
    "adaptive_sweep","cfo","cfo_correction","phase_noise", ...
    "iq_imbalance","iq_imbalance_correction","timing_offset", ...
    "pa_nonlinearity","link_adaptation_inner_loop", ...
    "link_adaptation_outer_loop","pathloss","shadow_fading", ...
    "los_propagation", ...
    "csi_reporting","cqi_reporting","pmi_reporting","ri_reporting", ...
    "cri_reporting","harq","transform_precoding", ...
    "waveform_windowing","beam_sweep","mu_mimo","ul_mu_mimo"];
assert(all(isfield(cfg.runtime.features, cellstr(requiredFeatures))), ...
    "Every scenario-operational waveform feature needs YAML authority.");
provenanceNames = string(cfg.runtime.ParameterProvenanceTable.Parameter);
for featureName = requiredFeatures
    assert(any(provenanceNames == ...
        "runtime.features." + featureName + ".Enabled"), ...
        "Feature %s is missing from runtime parameter provenance.", featureName);
end
sixgr.config.assertRuntimeFeatureAuthority(cfg);
assert(sixgr.config.assertRuntimeFeatureUse(cfg, "ptrs", true, ...
    "test_runtime_consumer"));
localAssertThrows(@() sixgr.config.assertRuntimeFeatureUse(cfg, ...
    "ptrs", false, "test_runtime_consumer_override"), ...
    "sixgr:config:YAMLFeatureExecutionMismatch");
featureBypass = cfg;
featureBypass.phy.srs.enable = ~featureBypass.runtime.features.srs.Enabled;
localAssertThrows(@() sixgr.config.assertRuntimeFeatureAuthority( ...
    featureBypass), "sixgr:config:YAMLFeatureAuthorityBypassed");

% Evidence consumers use the canonical authority even if a stale legacy
% alias is introduced after configuration validation.
stale = cfg;
stale.phy.pdsch.nLayers = 1;
stale.phy.pdsch.numLayers = 1;
stale.phy.pdsch.modulation = "QPSK";
stale.phy.pdsch.mcsIndex = 0;
configured = sixgr.mimo.buildMIMOConfigFromScenario(stale);
dl = configured(strcmpi(string(configured.Direction), "DL"), :);
assert(height(dl) == 1 && dl.ConfiguredLayers == 2 && ...
    dl.ConfiguredMCS == 20 && dl.ConfiguredInitialMCS == 0 && ...
    dl.ConfiguredMaximumMCS == 20 && ...
    strcmpi(string(dl.ConfiguredModulation), "256QAM"));

% Contradictory source aliases fail before any waveform execution.
badSource = scenario.toStruct();
badSource.pdsch.layer_count = 1;
localAssertThrows(@() sixgr.config.installRuntimeOperatingAuthority(cfg, badSource), ...
    "sixgr:config:ContradictoryRuntimeAuthority");
badSource = scenario.toStruct();
badSource.canonical_control.pdsch.layer_count = 1;
badSource.canonical_control.pdsch.rank = 1;
localAssertThrows(@() sixgr.config.installRuntimeOperatingAuthority(cfg, badSource), ...
    "sixgr:config:ContradictoryRuntimeAuthority");
badSource = scenario.toStruct();
badSource.canonical_control.pdsch.xoh_pdsch = ...
    double(badSource.pdsch.xoh_pdsch) + 6;
localAssertThrows(@() sixgr.config.installRuntimeOperatingAuthority(cfg, badSource), ...
    "sixgr:config:ContradictoryRuntimeAuthority");
badSource = scenario.toStruct();
badSource.reference_signals.csi_reporting_enabled = false;
localAssertThrows(@() sixgr.config.installRuntimeOperatingAuthority(cfg, badSource), ...
    "sixgr:config:ContradictoryRuntimeAuthority");
badSource = scenario.toStruct();
badSource.reference_signals.tracking_rs_enabled = true;
badSource.reference_signals.trs_enabled = false;
localAssertThrows(@() sixgr.config.installRuntimeOperatingAuthority(cfg, badSource), ...
    "sixgr:config:ContradictoryRuntimeAuthority");

ra = sixgr.mac.ra.RAConfig(cfg, "UEId", 1, "AttemptId", 1);
assert(ra.Msg2PDSCH.EnablePTRS && ra.Msg3PUSCH.EnablePTRS && ...
    ra.Msg4PDSCH.EnablePTRS && ra.SetupCompletePUSCH.EnablePTRS, ...
    "YAML PT-RS authority must reach SIB/RA data-channel waveform objects.");

grant = struct( ...
    "Direction", "DL", "GrantContextId", "runtime-authority-test", ...
    "UEIndex", 1, "RNTI", 41, "ServingCell", 1, ...
    "Frame", 1, "Slot", 1, "NumLayers", 2, ...
    "PRBSet", 0:3, "SymbolAllocation", [2 12], ...
    "Modulation", "256QAM", "MCSIndex", 20, ...
    "TargetCodeRate", cfg.runtime.phy.dl.TargetCodeRate, ...
    "TBSBits", 1024, "TBSBytes", 128);
frozen = sixgr.phy.grant.freezePHYGrant(cfg, "DL", grant, ...
    "Frame", 1, "Slot", 1, "SNR_dB", 20);
assert(string(frozen.ConfigurationAuthority.RuntimeOperatingAuthoritySHA256) == ...
    string(cfg.runtime.OperatingAuthoritySHA256));

replay = grant;
replay.PHYGrant = frozen;
changed = cfg;
changed.runtime.OperatingAuthoritySHA256 = repmat('f', 1, 64);
localAssertThrows(@() sixgr.phy.grant.freezePHYGrant( ...
    changed, "DL", replay, "Frame", 1, "Slot", 1, "SNR_dB", 20), ...
    "sixgr:phy:grant:FrozenConfigurationAuthorityMismatch");

ok = true;
end

function localAssertThrows(fcn, identifier)
didThrow = false;
try
    fcn();
catch ME
    didThrow = strcmp(string(ME.identifier), string(identifier));
    if ~didThrow
        rethrow(ME);
    end
end
assert(didThrow, "Expected typed error %s.", identifier);
end
