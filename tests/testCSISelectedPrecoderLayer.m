function ok=testCSISelectedPrecoderLayer()
% Closed-form two-layer channel fixtures; not primary waveform results.
request=struct('ReportConfigID',"layer-measurement-fixture",'Epoch',0, ...
    'CodebookType',"typeI-SinglePanel",'Ports',2,'Rank',2, ...
    'ReportQuantity',"cri-RI-LI-PMI-CQI",'NumCSIResources',1, ...
    'FrequencyGranularity',"wideband",'UCIChannel',"PUCCH");
W=eye(2)/sqrt(2);
cfg=struct('Strict',false,'MaxRank',2,'RankDomain',2, ...
    'CandidateMatrices',W,'CandidateIndices',0, ...
    'ReportConfiguration',request,'FeedbackOverheadWeight',0);
H=diag([4 1]);
csi=sixgr.mimo.buildCSIFeedback(H,.1,cfg);
assert(csi.RI==2 && csi.LI==0, ...
    'LI must identify the stronger first layer, not rank minus one.');
assert(max(abs(csi.SelectionInfo.SelectedSINRPerRELayer-[80 5]),[],'all')<1e-10);
decoded=csi.CSIReportConfiguration.decode(csi.CSIPart1Bits,csi.CSIPart2Bits);
assert(decoded.LI==0);
other=sixgr.mimo.buildCSIFeedback(diag([1 4]),.1,cfg);
assert(other.LI==1 && other.PMI==csi.PMI && other.RI==csi.RI, ...
    'Measured layer order must change LI without changing rank or precoder.');
cfg.FeedbackOverheadWeight=.4;
penalized=sixgr.mimo.buildCSIFeedback(H,.1,cfg);
assert(abs(penalized.WidebandSINR_dB-csi.WidebandSINR_dB)<1e-12 && ...
    penalized.CQI==csi.CQI, ...
    'Rank selection overhead must not be subtracted from receiver SINR.');
ok=true;
correlated=sixgr.mimo.buildCSIFeedback([1 .95;.95 1],.1,cfg);
expectedSE=mean(sum(log2(1+correlated.SelectionInfo.SelectedSINRPerRELayer),2));
assert(abs(correlated.SelectionInfo.SelectedMetric-expectedSE)<1e-12, ...
    'Rank/PMI selection must use the actual linear receiver layer SINR, not ideal joint-decoder log-det capacity.');
end
