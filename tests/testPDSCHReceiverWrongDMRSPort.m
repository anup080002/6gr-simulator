function ok = testPDSCHReceiverWrongDMRSPort()
%TESTPDSCHRECEIVERWRONGDMRSPORT Wrong reference-port binding must fail.

setup6GRSimToolkit("Verbose", false);
fixture = StrictPDSCHChainFixture.create(2);
tx = sixgr.pdsch.PDSCHTransmitter( ...
    fixture.TransportBlocks,fixture.Assignment,fixture.ResourcePlan, ...
    fixture.Carrier,fixture.ReferenceConfig, ...
    "PrecoderBundle",fixture.PrecoderBundle);
correctDMRS = tx.DMRSPortSymbols;
assert(size(correctDMRS,1) == 2 && ~isempty(correctDMRS), ...
    "Rank-2 fixture must expose two generated physical-port DM-RS streams.");
wrongDMRS = [ ...
    0.5j*correctDMRS(1,:) + sqrt(0.75)*correctDMRS(2,:); ...
    0.5j*correctDMRS(2,:) + sqrt(0.75)*correctDMRS(1,:)];
wrongGrid = tx.Grid;
for port = 1:size(wrongGrid,3)
    plane = wrongGrid(:,:,port);
    plane(tx.DMRSIndices + 1) = wrongDMRS(port,:).';
    wrongGrid(:,:,port) = plane;
end
ofdmOptions = fixture.ReferenceConfig.get("OFDMOptions");
[wrongWaveform,~] = sixgr.phy.waveform.ofdmModulate( ...
    fixture.Carrier,wrongGrid,ofdmOptions{:});
rx = sixgr.pdsch.PDSCHReceiver( ...
    wrongWaveform,fixture.Assignment,fixture.ResourcePlan,fixture.Carrier, ...
    fixture.ReferenceConfig,fixture.ReceiverConfig, ...
    "CodingPlans",tx.CodingPlans, ...
    "PrecoderBundle",fixture.PrecoderBundle);
assert(~rx.CRCPass && rx.CRCError, ...
    "Wrong DM-RS port binding must return a controlled CRC failure.");
fprintf("PDSCH strict RX wrong DM-RS port: controlled CRC failure pass\n");
ok = true;
end
