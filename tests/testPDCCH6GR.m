function ok = testPDCCH6GR()
%TESTPDCCH6GR Short focused regression suite for the 6GR PDCCH study path.

setup6GRSimToolkit("Verbose", false);

testDeterministicMappingReproducibility();
testCandidateGenerationStaysWithinBounds();
testCRCAndPayloadScramblingToggles();
testDMRSDoesNotCollideWithPayload();
testBlindDetectionHighSNRAndSNRSanity();
testInterSlotRepetitionNoWorseThanNone();
testRunnerIntegrationArtifacts();

ok = true;
end

function testDeterministicMappingReproducibility()
cfg = localBaseCfg();
ctrl = sixgr.ctrl.ControlChannelConfig(cfg);
[regT, ~] = sixgr.ctrl.REGIndexer(ctrl);
bundleT = sixgr.ctrl.REGBundleMapper(regT, ctrl.CORESET);
map1 = sixgr.ctrl.CCEToREGMapper(ctrl, regT, bundleT);
map2 = sixgr.ctrl.CCEToREGMapper(ctrl, regT, bundleT);
assert(isequaln(map1, map2), "CCE-to-REG mapping must be deterministic for identical inputs.");
end

function testCandidateGenerationStaysWithinBounds()
cfg = localBaseCfg();
ctrl = sixgr.ctrl.ControlChannelConfig(cfg);
[regT, ~] = sixgr.ctrl.REGIndexer(ctrl);
cceMap = sixgr.ctrl.CCEToREGMapper(ctrl, regT);
[candT, ~] = sixgr.ctrl.PDCCHCandidateGenerator(ctrl, ctrl.SearchSpaces(1), cceMap, 1);
valid = candT(candT.CandidateValid, :);
assert(all(valid.StartCCE >= 0), "Candidate start CCE must be nonnegative.");
assert(all(valid.EndCCE < height(cceMap)), "Candidate CCE span must remain within CORESET bounds.");
end

function testCRCAndPayloadScramblingToggles()
cfg = localBaseCfg();
ctrl = sixgr.ctrl.ControlChannelConfig(cfg);
payload = sixgr.ctrl.ControlPayloadBuilder(ctrl, "Seed", 44);
crcOn = sixgr.ctrl.CRCAttachAndScramble(payload.InformationBits, ctrl);
ctrlNoCRC = ctrl;
ctrlNoCRC.CRCScramblingEnabled = false;
crcOff = sixgr.ctrl.CRCAttachAndScramble(payload.InformationBits, ctrlNoCRC);
assert(~isequal(crcOn.BitsWithCRC, crcOff.BitsWithCRC), ...
    "CRC scrambling toggle must change the protected bit stream.");

scrOn = sixgr.ctrl.PayloadScrambler(crcOn.BitsWithCRC, ctrl, struct("SlotNumber",1,"SearchSpaceID",1));
ctrlNoScr = ctrl;
ctrlNoScr.PayloadScramblingEnabled = false;
scrOff = sixgr.ctrl.PayloadScrambler(crcOn.BitsWithCRC, ctrlNoScr, struct("SlotNumber",1,"SearchSpaceID",1));
assert(~isequal(scrOn.Bits, scrOff.Bits), ...
    "Payload scrambling toggle must change the coded bit stream.");
end

function testDMRSDoesNotCollideWithPayload()
cfg = localBaseCfg();
ctrl = sixgr.ctrl.ControlChannelConfig(cfg);
[regT, reT] = sixgr.ctrl.REGIndexer(ctrl);
cceMap = sixgr.ctrl.CCEToREGMapper(ctrl, regT);
[candT, ~] = sixgr.ctrl.PDCCHCandidateGenerator(ctrl, ctrl.SearchSpaces(1), cceMap, 1);
target = table2struct(candT(find(candT.CandidateValid, 1, "first"), :));
resources = localCandidateResources(target, regT, reT, cceMap, ctrl);
dmrs = sixgr.ctrl.PDCCHDMRS(ctrl, resources.RETable, struct("SlotNumber",1,"CandidateIndex",0,"SearchSpaceID",1));
payloadT = resources.RETable(dmrs.PayloadREMask, :);
dmrsKeys = string(dmrs.Locations.Symbol) + "_" + string(dmrs.Locations.Subcarrier) + "_" + string(dmrs.Locations.SlotIndex);
payloadKeys = string(payloadT.Symbol) + "_" + string(payloadT.Subcarrier) + "_" + string(payloadT.SlotIndex);
assert(isempty(intersect(dmrsKeys, payloadKeys)), "DMRS REs must not collide with payload REs.");
end

function testBlindDetectionHighSNRAndSNRSanity()
cfg = localBaseCfg();
scenarioMatrix = [ ...
    struct("ScenarioID","snr_low", "AggregationLevel",4, "CORESETDuration",2, "MappingType","noninterleaved", "FrequencyAllocationMode","contiguous", "RepetitionMode","none", "SNRdB",0, "ChannelModel","AWGN", "SearchSpaceType","USS", "DMRSVariant","single_port_density_3_per_rb", "REGBundleSize",2, "NumREGPerCCE",6, "MRSSMode","exclusive_6gr", "NumTrials",1)
    struct("ScenarioID","snr_high", "AggregationLevel",4, "CORESETDuration",2, "MappingType","noninterleaved", "FrequencyAllocationMode","contiguous", "RepetitionMode","none", "SNRdB",25, "ChannelModel","AWGN", "SearchSpaceType","USS", "DMRSVariant","single_port_density_3_per_rb", "REGBundleSize",2, "NumREGPerCCE",6, "MRSSMode","exclusive_6gr", "NumTrials",1)
    ];
out = sixgr.ctrl.runPDCCHStudyLLS(cfg, "ScenarioMatrix", scenarioMatrix, "WriteOutputs", false, "Verbose", false);
snrSorted = sortrows(out.SummaryBySNR, "SNRdB");
assert(issorted(double(snrSorted.mean_DetectionProbability)), ...
    "Detection probability should be nondecreasing across the short SNR sanity sweep.");
assert(any(double(snrSorted.SNRdB) == 25 & double(snrSorted.mean_DetectionProbability) > 0.5), ...
    "High-SNR baseline case should decode successfully.");
end

function testInterSlotRepetitionNoWorseThanNone()
cfg = localBaseCfg();
scenarioMatrix = [ ...
    struct("ScenarioID","rep_none", "AggregationLevel",4, "CORESETDuration",2, "MappingType","noninterleaved", "FrequencyAllocationMode","contiguous", "RepetitionMode","none", "SNRdB",0, "ChannelModel","AWGN", "SearchSpaceType","USS", "DMRSVariant","single_port_density_3_per_rb", "REGBundleSize",2, "NumREGPerCCE",6, "MRSSMode","exclusive_6gr", "NumTrials",1)
    struct("ScenarioID","rep_inter", "AggregationLevel",4, "CORESETDuration",2, "MappingType","noninterleaved", "FrequencyAllocationMode","contiguous", "RepetitionMode","inter_slot", "SNRdB",0, "ChannelModel","AWGN", "SearchSpaceType","USS", "DMRSVariant","single_port_density_3_per_rb", "REGBundleSize",2, "NumREGPerCCE",6, "MRSSMode","exclusive_6gr", "NumTrials",1)
    ];
out = sixgr.ctrl.runPDCCHStudyLLS(cfg, "ScenarioMatrix", scenarioMatrix, "WriteOutputs", false, "Verbose", false);
noneRow = out.SummaryByScenario(out.SummaryByScenario.RepetitionMode == "none", :);
repRow = out.SummaryByScenario(out.SummaryByScenario.RepetitionMode == "inter_slot", :);
assert(double(repRow.DetectionProbability) >= double(noneRow.DetectionProbability), ...
    "Inter-slot repetition should not underperform no repetition in the static AWGN sanity case.");
end

function testRunnerIntegrationArtifacts()
tmp = tempname;
mkdir(tmp);
cleanupObj = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

repoRoot = fileparts(fileparts(mfilename("fullpath")));
baseScenario = strrep(fullfile(repoRoot, "simulator", "configs", "scenarios", "pdcch_6gr_study.yaml"), "\", "/");
scenarioPath = fullfile(tmp, "pdcch6gr_runner_smoke.yaml");
scenarioCfg = struct();
scenarioCfg.inherits = {baseScenario};
scenarioCfg.meta = struct( ...
    "scenario_id", "pdcch6gr_runner_smoke", ...
    "description", "Short 6GR PDCCH runner integration smoke.");
scenarioCfg.simulation = struct("monte_carlo_iterations", 1, "snr_db", 20);
localWriteJSON(scenarioPath, scenarioCfg);

out = sixgr.lls6g.runners.runSingle(scenarioPath, tmp, "pdcch6gr_runner_smoke");
assert(logical(out.Ok), "6GR PDCCH runner integration smoke must complete successfully.");
runFolder = char(out.RunFolder);
assert(exist(fullfile(runFolder, "air_interface", "csv", "pdcch_trials.csv"), "file") == 2, ...
    "Runner must export canonical air_interface/csv/pdcch_trials.csv.");
pdcchT = readtable(fullfile(runFolder, "air_interface", "csv", "pdcch_trials.csv"));
assert(all(ismember([1 2 4 8 16], unique(double(pdcchT.AggregationLevel)).')), ...
    "PDCCH blind-decode runner must exercise aggregation levels 1, 2, 4, 8, and 16.");
assert(any(double(pdcchT.BlindDecodeCount) > 1), ...
    "PDCCH blind-decode runner must report real candidate-search counts, not a single known-location decode.");
assert(exist(fullfile(runFolder, "reports", "csv", "pdcch_control_outputs.csv"), "file") == 2, ...
    "Runner must export pdcch_control_outputs.csv.");
pdcchOut = readtable(fullfile(runFolder, "reports", "csv", "pdcch_control_outputs.csv"), ...
    "VariableNamingRule", "preserve");
assert(all(ismember(["CategoryCode","MetricKey","Availability","CountsTowardCoverage","SourceArtifact"], ...
    string(pdcchOut.Properties.VariableNames))), ...
    "pdcch_control_outputs.csv must be the category-F metric output table, not the standalone study summary.");
requiredObserved = ["false_alarm_probability","blocking_probability","blind_decode_count", ...
    "non_overlapped_cce_usage","aggregation_level_distribution","dci_size_distribution", ...
    "control_capacity_under_load","coreset_utilization","control_latency", ...
    "pdcch_monitoring_energy","invalid_detection_power_cost"];
for i = 1:numel(requiredObserved)
    mask = string(pdcchOut.MetricKey) == requiredObserved(i);
    assert(any(mask), "PDCCH control output is missing metric '%s'.", requiredObserved(i));
    assert(any(logical(pdcchOut.CountsTowardCoverage(mask))), ...
        "PDCCH control metric '%s' must count toward category-F coverage.", requiredObserved(i));
end
coverage = readtable(fullfile(runFolder, "reports", "csv", "lls_output_spec_coverage.csv"), ...
    "VariableNamingRule", "preserve");
catF = coverage(string(coverage.CategoryCode) == "F", :);
assert(height(catF) == 16, "Category F must retain all 16 cataloged PDCCH/control metrics.");
coveredF = sum(logical(catF.CountsTowardCoverage));
assert(coveredF >= 11, ...
    "Category F must cover at least the 11 runtime-backed PDCCH/control metrics; observed %d/16.", coveredF);
assert(exist(fullfile(runFolder, "reports", "csv", "pdcch6gr_per_candidate_results.csv"), "file") == 2, ...
    "Runner must export the detailed per-candidate results.");
end

