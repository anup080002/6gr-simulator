function ok = testPHYSignalDiagnostic()
%TESTPHYSIGNALDIAGNOSTIC Verify truthful same-trial PHY snapshot/export gates.

setup6GRSimToolkit("Verbose", false);
rng(730001, "twister");

demoPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "webgui_phy_diagnostic_demo.yaml");
demoScenario = sixgr.lls6g.config.loadScenarioConfig(demoPath);
demoCfg = sixgr.lls6g.buildInternalConfig(demoScenario, tempname);
assert(logical(demoCfg.outputs.phySignalDiagnosticRequested) && ...
    logical(demoCfg.outputs.phySignalDiagnosticCaptureReady) && ...
    logical(demoCfg.outputs.phySignalDiagnosticEnabled) && ...
    strlength(string(demoCfg.outputs.phySignalDiagnosticUnavailableReason)) == 0, ...
    "The WebGUI demo scenario must resolve every explicit PHY diagnostic capture gate.");

badPrerequisiteCfg = demoScenario.toStruct();
badPrerequisiteCfg.run_control.raw_iq_capture_enable = false;
threwPrerequisite = false;
prerequisiteFailure = "";
try
    sixgr.lls6g.config.validateScenarioConfig(badPrerequisiteCfg, ...
        "Kind", "scenario", "AllowPartial", false, "Context", "diagnostic_missing_gate_test");
catch ME
    threwPrerequisite = strcmp(string(ME.identifier), ...
        "sixgr:lls6g:config:PHYSignalDiagnosticPrerequisites");
    prerequisiteFailure = string(ME.identifier) + ": " + string(ME.message);
end
assert(threwPrerequisite, ...
    "An explicitly requested diagnostic must fail when any capture prerequisite is disabled. " + ...
    "Observed: " + prerequisiteFailure);

cfg = localConfig();
[tx, rxWave, rx, constellationT, context] = localTrialEvidence();
snapshot = sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    cfg, "DL", tx, rxWave, rx, constellationT, context);

% Production shared-stream reception withholds executed coefficients from
% the practical receiver and appends them only after CRC completion.
practicalContext=context;
runtimeFields=string(fieldnames(practicalContext));
runtimeFields=runtimeFields(startsWith(runtimeFields,"RuntimeChannel"));
practicalContext=rmfield(practicalContext,cellstr(runtimeFields));
practicalSnapshot=sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    cfg,"DL",tx,rxWave,rx,constellationT,practicalContext);
assert(isempty(practicalSnapshot.SourceTable(ismember(string( ...
    practicalSnapshot.SourceTable.Panel),["true_channel_impulse_response", ...
    "runtime_channel_angles","time_varying_channel_impulse_response"]),:)), ...
    'Practical receiver diagnostics must not consume executed channel-oracle arrays.');
augmentedSnapshot=sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    cfg,"DL",struct(),[],struct(),table(),context,practicalSnapshot);
augmentedPanels=string(augmentedSnapshot.SourceTable.Panel);
augmentedPostChannel=augmentedSnapshot.SourceTable( ...
    augmentedPanels=="time_domain" & string(augmentedSnapshot.SourceTable.Series)=="post_channel",:);
assert(any(augmentedPanels=="true_channel_impulse_response") && ...
    any(augmentedPanels=="runtime_channel_angles") && ...
    any(augmentedPanels=="time_varying_channel_impulse_response") && ...
    height(augmentedPostChannel)==256 && ...
    max(abs(complex(double(augmentedPostChannel.IValue),double(augmentedPostChannel.QValue))- ...
    context.PostChannelWaveform(1:256)))<1e-12 && ...
    augmentedSnapshot.SnapshotID==practicalSnapshot.SnapshotID, ...
    'Post-decode augmentation must add actual channel and post-channel waveform evidence without changing trial identity.');

assert(logical(snapshot.Available), ...
    "Complete runtime PHY arrays from one trial must produce a diagnostic snapshot.");
T = snapshot.SourceTable;
assert(istable(T) && ~isempty(T), "The diagnostic snapshot must expose its source table.");
assert(numel(unique(string(T.SnapshotID), "stable")) == 1, ...
    "Every diagnostic panel must retain one exact same-trial SnapshotID.");
assert(all(string(T.CurveConstruction) == "runtime_same_trial_phy_signal_snapshot"), ...
    "The diagnostic must disclose same-trial runtime construction.");
assert(all(string(T.truth_status) == "real_lls_evidence"), ...
    "The diagnostic must be labeled as actual LLS evidence.");
assert(all(string(T.SourceArtifact) == "runtime_phy_arrays_same_trial"), ...
    "The diagnostic must disclose runtime PHY array provenance.");

txTime = T(string(T.Panel) == "time_domain" & string(T.Series) == "tx", :);
rxTime = T(string(T.Panel) == "time_domain" & string(T.Series) == "rx", :);
assert(height(txTime) == height(rxTime) && height(txTime) == 256, ...
    "Time-domain capture must retain the configured bounded contiguous window.");
assert(isequal(double(txTime.SampleIndex), (1:height(txTime)).') && ...
    isequal(double(rxTime.SampleIndex), (1:height(rxTime)).'), ...
    "TX/RX time-domain samples must be contiguous, not linspace previews.");

txSpectrum = T(string(T.Panel) == "spectrum" & string(T.Series) == "tx", :);
assert(height(txSpectrum) == 256 && all(isfinite(double(txSpectrum.XValue))), ...
    "FFT evidence must be computed from the bounded contiguous sample window.");

postChannelT = T(string(T.Panel) == "time_domain" & ...
    string(T.Series) == "post_channel", :);
expectedPostChannel = context.PostChannelWaveform(1:256);
assert(height(postChannelT) == 256 && ...
    max(abs(complex(double(postChannelT.IValue), double(postChannelT.QValue)) - ...
    expectedPostChannel)) < 1e-12 && ...
    all(string(postChannelT.GridKind) == "exact_runtime_channel_output_waveform"), ...
    "Post-channel evidence must preserve the exact executed pre-receiver waveform.");

channelT = T(string(T.Panel) == "channel_estimate", :);
expectedH = rx.ChannelEstimate(:, 1, 1);
actualH = complex(double(channelT.IValue), double(channelT.QValue));
assert(isequal(double(channelT.SubcarrierIndex), (0:numel(expectedH)-1).') && ...
    isequal(double(channelT.MatlabSubcarrierIndex), (1:numel(expectedH)).') && ...
    max(abs(actualH - expectedH)) < 1e-12, ...
    "Fading-channel Hest rows must retain explicit zero-based NR and one-based MATLAB coordinates.");

gridT = T(string(T.Panel) == "channel_estimate_grid", :);
% Preserve zero entries from the receiver exactly. Log zero is -Inf and
% phase is undefined; a realmin floor must not manufacture a -6153 dB dip.
zeroRx=rx; zeroRx.ChannelEstimate(2:3,:,:,:)=0;
zeroSnapshot=sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    cfg,"DL",tx,rxWave,zeroRx,constellationT,context);
for panel=["channel_estimate","channel_estimate_grid"]
    zeroRows=zeroSnapshot.SourceTable(string(zeroSnapshot.SourceTable.Panel)==panel,:);
    mask=zeroRows.SubcarrierIndex==1 | zeroRows.SubcarrierIndex==2;
    assert(any(mask) && all(zeroRows.IValue(mask)==0 & zeroRows.QValue(mask)==0));
    assert(all(isinf(zeroRows.Magnitude_dB(mask)) & zeroRows.Magnitude_dB(mask)<0) && ...
        all(isnan(zeroRows.WrappedPhase_rad(mask))) && all(isnan(zeroRows.Phase_deg(mask))) && ...
        all(zeroRows.PhaseValueStatus(mask)=="undefined_zero_receiver_estimate"));
    assert(all(isfinite(zeroRows.Magnitude_dB(~mask))) && ...
        all(isfinite(zeroRows.UnwrappedPhaseFrequency_rad(~mask))));
end
assert(height(gridT) == numel(rx.ChannelEstimate), ...
    "Full channel-grid capture must persist every measured K-by-L-by-Rx-by-Tx sample.");
assert(all(double(gridT.CellID) == 321) && all(double(gridT.SFN) == 3) && ...
    all(double(gridT.AbsoluteSlot) == 67), ...
    "Every full-grid row must preserve cell, SFN, and absolute-slot identity.");
assert(isequal(unique(double(gridT.OFDMSymbolIndex), "stable"), (0:13).') && ...
    isequal(unique(double(gridT.SubcarrierInResourceBlock)), (0:11).'), ...
    "OFDM-symbol and subcarrier-in-RB coordinates must use explicit zero-based NR indexing.");
assert(all(isfinite(double(gridT.WrappedPhase_rad))) && ...
    all(isfinite(double(gridT.UnwrappedPhaseFrequency_rad))) && ...
    all(isfinite(double(gridT.UnwrappedPhaseTime_rad))) && ...
    numel(unique(string(gridT.GridSHA256))) == 1, ...
    "The persisted tensor must expose measured wrapped/unwrapped phase and one exact tensor digest.");

hhatTauT = T(string(T.Panel) == "estimated_channel_impulse_response", :);
expectedChannelSubcarriers = size(rx.ChannelEstimate, 1);
assert(height(hhatTauT) == expectedChannelSubcarriers && ...
    all(string(hhatTauT.GridKind) == ...
    "receiver_estimated_bandlimited_impulse_response"), ...
    "Hhat(tau) must be an explicitly labelled inverse transform of receiver Hest.");

trueTauT = T(string(T.Panel) == "true_channel_impulse_response", :);
expectedExecutedGain = reshape(context.RuntimeChannelPathGains(1,:,1,1), [], 1);
assert(height(trueTauT) == numel(context.RuntimeChannelPathDelays_s) && ...
    max(abs(complex(double(trueTauT.IValue), double(trueTauT.QValue)) - ...
    expectedExecutedGain)) < 1e-12 && ...
    max(abs(double(trueTauT.XValue) - ...
    context.RuntimeChannelPathDelays_s(:))) < 1e-18, ...
    "True H(tau) must come from the executed path-gain tensor and actual path delays.");

trueHfT = T(string(T.Panel) == "true_channel_frequency_response", :);
expectedFrequency = double(trueHfT.FrequencyOffset_Hz);
expectedTrueHf = exp(-1i .* 2 .* pi .* expectedFrequency .* ...
    reshape(context.RuntimeChannelPathDelays_s, 1, [])) * expectedExecutedGain;
assert(height(trueHfT) == expectedChannelSubcarriers && ...
    max(abs(complex(double(trueHfT.IValue), double(trueHfT.QValue)) - ...
    expectedTrueHf)) < 1e-12, ...
    "True H(f) must be computed only from executed complex path gains and delays.");

angleT = T(string(T.Panel) == "runtime_channel_angles", :);
assert(height(angleT) == numel(context.RuntimeChannelPathDelays_s) && ...
    max(abs(double(angleT.AzimuthDeparture_deg) - ...
        context.RuntimeChannelAnglesAoD_deg(:))) < 1e-12 && ...
    max(abs(double(angleT.AzimuthArrival_deg) - ...
        context.RuntimeChannelAnglesAoA_deg(:))) < 1e-12 && ...
    all(string(angleT.RuntimeChannelStateKey) == context.RuntimeChannelStateKey) && ...
    all(logical(angleT.RuntimeChannelReciprocityExact)) && ...
    all(string(angleT.GridSHA256) == context.RuntimeChannelPathGainsSHA256), ...
    "AoA/AoD rows must be bound to the same executed path-gain tensor and reciprocal state.");

ofdmT = T(string(T.Panel) == "ofdm_symbol_cp_samples", :);
assert(~isempty(ofdmT) && any(logical(ofdmT.IsCyclicPrefix)) && ...
    any(~logical(ofdmT.IsCyclicPrefix)) && ...
    all(double(ofdmT.UsefulSymbolLength_samples) == 16), ...
    "OFDM sample evidence must identify exact CP and useful-symbol ownership.");
timeChannelT = T(string(T.Panel) == ...
    "time_varying_channel_impulse_response", :);
assert(height(timeChannelT) == numel(context.RuntimeChannelPathGains) && ...
    numel(unique(double(timeChannelT.TimeIndex))) == 4, ...
    "Executed path-gain evidence must retain the bounded time dimension.");
dopplerT = T(string(T.Panel) == "doppler_spectrum", :);
assert(~isempty(dopplerT) && all(isfinite(double(dopplerT.DopplerFrequency_Hz))) && ...
    all(isfinite(double(dopplerT.Power_dB))), ...
    "Doppler evidence must be computed from the executed path-gain time series.");
spatialT = T(string(T.Panel) == "spatial_correlation_matrix", :);
assert(height(spatialT) == 2 && ...
    all(abs(double(spatialT.MagnitudeLinear) - 1) < 1e-12), ...
    "Spatial correlation must be calculated from the measured Hest tensor.");
equalizerT = T(string(T.Panel) == "equalizer_weights", :);
assert(height(equalizerT) == numel(rx.EqualizerInfo.EqualizerResult.W) && ...
    all(isfinite(double(equalizerT.EqualizerPostEqSINR_dB))), ...
    "Equalizer evidence must retain exact W and per-RE post-EQ SINR.");
decoderT = T(string(T.Panel) == "decoder_ber", :);
assert(height(decoderT) == 2 && ...
    isequal(sort(string(decoderT.DecoderStage)), ...
    sort(["pre_decoder_rate_matched";"post_decoder_transport_block"])) && ...
    all(double(decoderT.BitsCompared) > 0), ...
    "Pre/post decoder BER must compare aligned runtime bit domains.");
assert(all(double(T.SCS_kHz) == 30) && ...
    all(double(T.CarrierFrequency_Hz) == 3.5e9) && ...
    all(double(T.SlotsPerFrame) == 20), ...
    "Every diagnostic row must retain the resolved carrier/numerology reference plane.");

% Production scenario normalization uses lowercase frame.scs_khz and
% phy.fc_Hz.  The diagnostic must resolve those canonical paths even when a
% caller does not duplicate them into legacy channel fields or the TX carrier.
productionCfg = cfg;
productionCfg.channel = rmfield(productionCfg.channel, "carrierFrequencyHz");
productionCfg.frame = struct("scs_khz", 30);
productionCfg.phy.fc_Hz = 3.5e9;
productionTx = tx;
productionTx.Carrier = rmfield(productionTx.Carrier, "SubcarrierSpacing");
productionSnapshot = sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    productionCfg, "DL", productionTx, rxWave, rx, constellationT, context);
assert(logical(productionSnapshot.Available) && ...
    any(string(productionSnapshot.SourceTable.Panel) == ...
    "estimated_channel_impulse_response") && ...
    all(double(productionSnapshot.SourceTable.SCS_kHz) == 30) && ...
    all(double(productionSnapshot.SourceTable.CarrierFrequency_Hz) == 3.5e9), ...
    "Canonical production config paths must generate frequency/delay diagnostics without legacy aliases.");

postT = T(string(T.Panel) == "post_equalization_constellation", :);
assert(max(abs(double(postT.EqualizedI) - double(constellationT.EqualizedReal))) < 1e-12 && ...
    max(abs(double(postT.ReferenceI) - double(constellationT.ReferenceSymbolReal))) < 1e-12, ...
    "Post-EQ and reference constellation rows must retain aligned runtime symbols.");

scalarRx = rx;
scalarRx.ChannelEstimate = rx.ChannelEstimate(1);
scalarSnapshot = sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    cfg, "DL", tx, rxWave, scalarRx, constellationT, context);
assert(~logical(scalarSnapshot.Available) && ...
    string(scalarSnapshot.Reason) == "fading_channel_requires_grid_shaped_hest", ...
    "A scalar-expanded fading-channel estimate must fail closed.");

forbiddenRx = rx;
forbiddenRx.ChannelEstimateSource = "synthetic_fallback_hest";
forbiddenSnapshot = sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    cfg, "DL", tx, rxWave, forbiddenRx, constellationT, context);
assert(~logical(forbiddenSnapshot.Available) && ...
    contains(string(forbiddenSnapshot.Reason), "forbidden_provenance"), ...
    "Proxy or fallback channel-estimate provenance must be rejected.");

missingEstimatorRx = rx;
missingEstimatorRx.ChannelEstimateMethod = "";
missingEstimatorSnapshot = sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    cfg, "DL", tx, rxWave, missingEstimatorRx, constellationT, context);
assert(~logical(missingEstimatorSnapshot.Available) && ...
    string(missingEstimatorSnapshot.Reason) == "receiver_channel_estimator_provenance_incomplete", ...
    "Receiver Hest source and method provenance must be explicit.");

missingConstellationProvenance = removevars(constellationT, "truth_status");
missingConstellationSnapshot = sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    cfg, "DL", tx, rxWave, rx, missingConstellationProvenance, context);
assert(~logical(missingConstellationSnapshot.Available) && ...
    string(missingConstellationSnapshot.Reason) == ...
    "post_equalization_constellation_provenance_missing", ...
    "Constellation evidence without explicit real/runtime provenance must fail closed.");

conflictingConstellation = constellationT;
conflictingConstellation.ApproximationMode = repmat("fallback", height(conflictingConstellation), 1);
conflictingSnapshot = sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    cfg, "DL", tx, rxWave, rx, conflictingConstellation, context);
assert(~logical(conflictingSnapshot.Available) && ...
    startsWith(string(conflictingSnapshot.Reason), ...
    "post_equalization_constellation_provenance_conflict"), ...
    "A real-evidence label must not override a conflicting proxy/fallback provenance field.");

missingModelCfg = rmfield(cfg, "channel");
missingModelSnapshot = sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    missingModelCfg, "DL", tx, rxWave, rx, constellationT, context);
assert(~logical(missingModelSnapshot.Available) && ...
    string(missingModelSnapshot.Reason) == "channel_model_provenance_unavailable", ...
    "Missing channel-model provenance must not be interpreted as explicit AWGN.");

standaloneContext = rmfield(context, "UEIndex");
standaloneCfg = cfg;
standaloneCfg.lls6g = struct("users", struct("enabled", false, "n_users", 1));
standaloneSnapshot = sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    standaloneCfg, "DL", tx, rxWave, rx, constellationT, standaloneContext);
assert(logical(standaloneSnapshot.Available) && ...
    double(standaloneSnapshot.Metadata.UEIndex) == 1 && ...
    string(standaloneSnapshot.Metadata.UEIdentitySource) == ...
    "standalone_single_user_default", ...
    "A direct standalone link must receive a truthful single-user diagnostic tuple.");

disabledCfg = cfg;
disabledCfg.outputs.phySignalDiagnosticEnabled = false;
disabledSnapshot = sixgr.link.buildPHYSignalDiagnosticSnapshot( ...
    disabledCfg, "DL", tx, rxWave, rx, constellationT, context);
assert(~logical(disabledSnapshot.Available) && ...
    string(disabledSnapshot.Reason) == "capture_disabled_by_config", ...
    "The config gate must suppress capture without reconstructing evidence.");

tmp = tempname;
mkdir(tmp);
cleanupTmp = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>
cleanupPersistence = sixgr.util.persistenceScope(true); %#ok<NASGU>
diagnostics = struct( ...
    "DL", snapshot, ...
    "UL", localUnavailableSnapshot("UL"));
artifacts = sixgr.truth.exportPHYSignalDiagnostic(tmp, cfg, diagnostics);
layout = sixgr.report.resultLayout(tmp);
assert(logical(artifacts.DLAvailable) && ~logical(artifacts.ULAvailable), ...
    "Only directions with complete same-trial runtime evidence may render normally.");
assert(exist(fullfile(layout.ReportCSVDir, "phy_signal_diagnostic_source.csv"), "file") == 2, ...
    "The canonical diagnostic source CSV must be persisted.");
assert(exist(fullfile(layout.ReportImageDir, "dl_phy_signal_diagnostic.png"), "file") == 2, ...
    "A normal DL image must be emitted for complete evidence.");
assert(exist(fullfile(layout.ReportImageDir, "ul_phy_signal_diagnostic.png"), "file") ~= 2, ...
    "A normal UL image must not be emitted when UL evidence is missing.");
assert(exist(sixgr.visual.unavailableArtifactPath( ...
    fullfile(layout.ReportImageDir, "ul_phy_signal_diagnostic.png")), "file") ~= 2 && ...
    strlength(strtrim(string(artifacts.ULReason))) > 0, ...
    "Missing direction evidence must be suppressed as structured metadata, not a fake raster card.");

persisted = readtable(fullfile(layout.ReportCSVDir, ...
    "phy_signal_diagnostic_source.csv"), "TextType", "string");
assert(all(string(persisted.Direction) == "DL") && ...
    all(string(persisted.truth_status) == "real_lls_evidence"), ...
    "The canonical source CSV must not contain fallback rows for an unavailable direction.");
requiredPersistedColumns = ["DopplerFrequency_Hz","CorrelationDomain", ...
    "EqualizerREIndex","EqualizerPostEqSINR_dB","EqualizerAlgorithm", ...
    "DecoderStage","BitComparisonSource","KPIName","KPITextValue","KPIUnit", ...
    "AngleCoordinateFrame","AngleEvidenceSource","RuntimeChannelLinkKey", ...
    "RuntimeChannelStateKey","RuntimeChannelReciprocityExact", ...
    "RuntimeChannelReciprocityDirection","RuntimeChannelReciprocitySource", ...
    "RuntimeChannelReciprocityApproximationMode"];
assert(all(ismember(requiredPersistedColumns, string(persisted.Properties.VariableNames))), ...
    "The heterogeneous PHY diagnostic CSV must retain its declared panel schemas.");

% Runtime array capture is independent of legacy MATLAB raster creation.
% SaveFigures=false in the production runner must retain the exact source
% CSV for later deterministic contract materialization.
tmpSourceOnly = tempname;
mkdir(tmpSourceOnly);
cleanupSourceOnly = onCleanup(@() rmdir(tmpSourceOnly, "s")); %#ok<NASGU>
sourceOnly = sixgr.truth.exportPHYSignalDiagnostic( ...
    tmpSourceOnly, cfg, diagnostics, false);
sourceLayout = sixgr.report.resultLayout(tmpSourceOnly);
assert(logical(sourceOnly.DLAvailable) && ~logical(sourceOnly.ImagesRendered), ...
    "Source-only export must retain the valid runtime snapshot.");
assert(exist(fullfile(sourceLayout.ReportCSVDir, ...
    "phy_signal_diagnostic_source.csv"), "file") == 2, ...
    "Source-only export must persist exact same-trial runtime rows.");
assert(exist(fullfile(sourceLayout.ReportImageDir, ...
    "dl_phy_signal_diagnostic.png"), "file") ~= 2, ...
    "Source-only export must not create a legacy MATLAB PNG.");

top50 = sixgr.truth.exportTop50VisualizationEvidenceInventory(tmp, cfg);
assert(height(top50.ContractTable) == 50 && ...
    isequal(double(top50.ContractTable.VisualID), (1:50).'), ...
    "The output inventory must register every requested visualization exactly once.");
for visualID = [9,10,11,12,20,22,21,25,27,29,30,35,37,38,41]
    row = top50.InventoryTable(top50.InventoryTable.VisualID == visualID, :);
    assert(height(row) == 1 && row.AvailabilityStatus == "validated_reconstructible" && ...
        logical(row.PlotCanBeRegeneratedFromCSV), ...
        "Visual %d must be reproducible from the persisted same-trial diagnostic CSV.", visualID);
end

% A scalar mobility-Doppler timeline is not a measured spectrum.  Removing
% the diagnostic Doppler rows must therefore fail closed even if that
% unrelated scalar timeline is present.
persistedWithoutDoppler = persisted(string(persisted.Panel) ~= "doppler_spectrum", :);
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, ...
    "phy_signal_diagnostic_source.csv"), persistedWithoutDoppler);
scalarDoppler = table((0:3).', repmat(5.5, 4, 1), ...
    'VariableNames', {'Slot','DopplerHz'});
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, ...
    "doppler_time_variation_plot.csv"), scalarDoppler);
top50WithoutSpectrum = sixgr.truth.exportTop50VisualizationEvidenceInventory(tmp, cfg);
dopplerRow = top50WithoutSpectrum.InventoryTable( ...
    top50WithoutSpectrum.InventoryTable.VisualID == 22, :);
assert(height(dopplerRow) == 1 && ...
    dopplerRow.AvailabilityStatus == "missing_runtime_capture" && ...
    ~logical(dopplerRow.PlotCanBeRegeneratedFromCSV) && ...
    contains(dopplerRow.AuditNotes, "observation aperture"), ...
    "A scalar mobility Doppler must never be relabelled as a measured Doppler spectrum.");

ok = true;
end

function cfg = localConfig()
cfg = struct();
cfg.run = struct("runTag", "test_phy_signal_diagnostic");
cfg.outputs = struct( ...
    "phySignalDiagnosticEnabled", true, ...
    "phySignalDiagnosticWaveformSamples", 256, ...
    "phySignalDiagnosticFFTLength", 256, ...
    "phySignalDiagnosticChannelPoints", 256, ...
    "phySignalDiagnosticConstellationPoints", 64, ...
    "phySignalDiagnosticFullChannelGrid", true);
cfg.channel = struct( ...
    "model", "TDL", ...
    "tdlProfile", "TDL-C", ...
    "cdlProfile", "", ...
    "awgnOnly", false, ...
    "carrierFrequencyHz", 3.5e9);
cfg.frame = struct("scs_kHz", 30);
cfg.phy = struct("rnti", 4101);
end

function [tx, rxWave, rx, constellationT, context] = localTrialEvidence()
n = 512;
sampleRateHz = 30.72e6;
sampleIndex = (0:n-1).';
txWave = exp(1i .* 2 .* pi .* 0.037 .* sampleIndex) + ...
    0.1 .* exp(1i .* 2 .* pi .* 0.13 .* sampleIndex);
rxWave = 0.82 .* txWave .* exp(1i .* 0.21) + ...
    0.015 .* complex(randn(n, 1), randn(n, 1));
tx = struct( ...
    "Waveform", txWave, ...
    "OFDMInfo", struct("SampleRate", sampleRateHz, "Nfft", 16, ...
        "CyclicPrefixLengths", repmat(4, 1, 14), ...
        "SymbolLengths", repmat(20, 1, 14)), ...
    "OFDMWindowingSamples", 2, ...
    "Codeword", int8([0;1;0;1;1;0;0;1]), ...
    "Codewords", {{int8([0;1;0;1;1;0;0;1])}}, ...
    "TransportBlock", int8([1;0;1;1]), ...
    "TransportBlocks", {{int8([1;0;1;1])}}, ...
    "Carrier", struct("NCellID", 321, "SubcarrierSpacing", 30, "NStartGrid", 0));

k = 72;
l = 14;
subcarrier = (0:k-1).';
hest = exp(-0.002 .* subcarrier) .* exp(1i .* (0.02 .* subcarrier));
hest = repmat(hest, 1, l);
hest = reshape(hest, k, l, 1);
preEq = complex(randn(96, 1), randn(96, 1));
rx = struct( ...
    "ChannelEstimate", hest, ...
    "ChannelEstimateSource", "pdsch_dmrs_channel_estimate", ...
    "ChannelEstimateMethod", "nrChannelEstimate", ...
    "ChannelEstimateEngine", "matlab_5g_toolbox", ...
    "ChannelEstimateInterpolationMethod", "2d_dmrs_interpolation", ...
    "PDSCHRxSymbolsForEvidence", preEq, ...
    "PostEqSINR_dB", 12.3, ...
    "PostEqSINRSource", "pdsch_receiver_hest_noise_estimate", ...
    "PostEqSINRValueRole", "receiver_derived", ...
    "CRCPass", true, ...
    "CodewordLLR", [4;-3;2;-5;-2;3;6;-4], ...
    "CodewordLLRCell", {{[4;-3;2;-5;-2;3;6;-4]}}, ...
    "TransportBlock", int8([1;0;1;1]), ...
    "TransportBlocks", {{int8([1;0;1;1])}}, ...
    "EqualizerInfo", struct("EqualizerResult", struct( ...
