function ok=testHARQLiveCompactPublication()
% Declared accounting fixtures, not measured PHY or a reliability campaign.
root=tempname; mkdir(root);
cleanup=onCleanup(@()rmdir(root,'s')); %#ok<NASGU>
raw=struct('DL',table([2;2;3],[41;42;43],[1;0;NaN],[1;2;1],[40;NaN;40], ...
    'VariableNames',{'Frame','Slot','CRCPass','SweepPointIndex','SNR_dB'}),'UL',table());
state=struct('SharedGNBUCIHARQTable',table(),'ControlTrials',struct('PUCCH',table()));
first=sixgr.truth.exportLLSLiveDerivedTables(struct(),root,raw,struct(),struct(), ...
    state,"harq_observations");
T=first.HARQ.TimelineTable;
assert(height(T)==3 && isequal(T.Slot,[41;42;43]) && ...
    isequaln(T.CRCPass,[1;0;NaN]) && isequaln(T.SNR_dB,[40;NaN;40]) && ...
    isequal(T.SweepPointIndex,[1;2;1]));
assert(all(isnan(T.CombinedDecodeOK)) && ...
    first.HARQPopulations.TransportAttemptsObserved==3 && ...
    isnan(first.HARQPopulations.LogicalACKAssociations), ...
    'A receiver CRC must never fabricate transmitter-observed ACK feedback.');
assert(~isfile(fullfile(root,'reports','csv','live_rank_estimation_stats.csv')), ...
    'Compact HARQ publication must not execute the heavy report path.');
state.SharedGNBUCIHARQTable=table(["tx41";"tx42"],["ACK";"DTX"], ...
    'VariableNames',{'TransmissionID','FeedbackOutcome'});
state.ControlTrials.PUCCH=table("receiver_only",0,NaN, ...
    'VariableNames',{'PhysicalPUCCHOccasionId','PUCCHTransmissionPrepared','ExpectedBitCount'});
second=sixgr.truth.exportLLSLiveDerivedTables(struct(),root,raw,struct(),struct(), ...
    state,"harq_observations");
assert(isequaln(second.HARQ.TimelineTable,T) && ...
    second.HARQPopulations.LogicalFeedbackAssociations==2 && ...
    second.HARQPopulations.LogicalACKAssociations==1 && ...
    second.HARQPopulations.LogicalACKRate==.5 && ...
    second.HARQPopulations.PhysicalPUCCHTransmissions==0);
saved=sixgr.util.csvReadTable(second.HARQPopulationPath);
assert(saved.TransportAttemptsObserved==3 && saved.LogicalACKAssociations==1);
ok=true; disp('HARQ_LIVE_COMPACT_PUBLICATION_PASS');
end
