function ok = testPDSCHReceiverWrongPRGMap()
%TESTPDSCHRECEIVERWRONGPRGMAP Stale PRG matrix map must fail.

setup6GRSimToolkit("Verbose", false);
fixture = StrictPDSCHChainFixture.create(2, ...
    "NPRB",4,"FrequencySelective",true,"TransportBlockSize",1000);
tx = sixgr.pdsch.PDSCHTransmitter( ...
    fixture.TransportBlocks,fixture.Assignment,fixture.ResourcePlan, ...
    fixture.Carrier,fixture.ReferenceConfig, ...
    "PrecoderBundle",fixture.PrecoderBundle);
wrongBundle = StrictPDSCHChainFixture.reversePRGBundle( ...
    fixture.PrecoderBundle);
rx = sixgr.pdsch.PDSCHReceiver( ...
    tx.Waveform,fixture.Assignment,fixture.ResourcePlan,fixture.Carrier, ...
    fixture.ReferenceConfig,fixture.ReceiverConfig, ...
    "CodingPlans",tx.CodingPlans, ...
    "PrecoderBundle",wrongBundle);
assert(~rx.CRCPass && rx.CRCError, ...
    "Wrong PRG mapping must return a controlled CRC failure.");
fprintf("PDSCH strict RX wrong PRG map: controlled CRC failure pass\n");
ok = true;
end
