function ok = testPUSCHMultiLayerPostEqSINR()
%TESTPUSCHMULTILAYERPOSTEQSINR Validate rank-2 PUSCH receiver SINR evidence.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
if ~localHaveRequired5G()
    warning("testPUSCHMultiLayerPostEqSINR:Missing5G", ...
        "Skipping rank-2 PUSCH SINR test because required 5G Toolbox APIs are unavailable.");
    ok = true;
    return;
end

rng(6384, "twister");
cfg = sixgr.config.defaultConfig();
cfg.run.shortRun = true;
cfg.run.strictMode = true;
cfg.run.noProxyTruthContract = true;
cfg.run.strictNoiseVarianceRequired = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.phy.nTxAnt = 4;
cfg.phy.nRxAnt = 64;
cfg.channel.nTxAnt = 4;
cfg.channel.nRxAnt = 64;
cfg.scenario.ue.nTxAnt = 4;
cfg.antenna.ue.numElements = 4;
cfg.phy.carrier.NSizeGrid = 12;
cfg.phy.carrier.SubcarrierSpacing = 30;
cfg.phy.pusch.prbSet = 0:5;
cfg.phy.pusch.symbolAllocation = [0 10];
cfg.phy.pusch.modulation = "QPSK";
cfg.phy.pusch.codeRate = 0.30;
cfg.phy.pusch.mcsIndex = 4;
cfg.phy.pusch.numLayers = 2;
cfg.phy.pusch.nLayers = 2;
cfg.phy.pusch.numAntennaPorts = 4;
cfg.phy.pusch.numPorts = 4;
% Strict multi-layer execution requires the scenario to declare the
% logical DM-RS port pool.  Do not rely on the scalar rank-one default.
cfg.phy.pusch.dmrs.portSet = [0 1];
cfg.phy.pusch.dmrs.DMRSPortSet = [0 1];
cfg.phy.pusch.transmissionScheme = "codebook";
cfg.phy.pusch.transformPrecoding = false;
cfg.phy.pusch.TPMI = 0;
cfg.phy.pusch.PMI = 0;
cfg.phy.pusch.enablePTRS = false;
cfg.phy.pusch.equalizer = "MMSE";
cfg.phy.channelEstimation.method = "LS";

[tx, ~] = sixgr.phy.ul.PUSCH_Tx(cfg, "CompactOutput", false);
assert(size(tx.Waveform, 2) == 4, ...
    "Rank-2 codebook fixture must radiate through all four configured UE ports.");

% A deterministic full-rank 4x64 flat channel exercises the actual
% multi-port estimator/equalizer without count-only expansion.
nRx = 64;
nTx = 4;
H = exp(1i * 2 * pi .* ((0:nRx-1).' * (0:nTx-1)) ./ nRx) ./ sqrt(nTx);
rxClean = tx.Waveform * H.';
snr_dB = 20;
signalPower = mean(abs(rxClean(:)).^2, "omitnan");
noiseVarTime = signalPower ./ (10.^(snr_dB ./ 10));
noise = sqrt(noiseVarTime ./ 2) .* ...
    (randn(size(rxClean)) + 1i .* randn(size(rxClean)));
rxWaveform = rxClean + noise;

[rx, ~] = sixgr.phy.ul.PUSCH_Rx(rxWaveform, cfg, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "PUSCHIndices", tx.PUSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", noiseVarTime, ...
    "NoiseVarDomain", "time", ...
    "CodingLayout", tx.CodingLayout, ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true);

rawSINR = double(rx.PostEqSINRRawEqualizer_dB);
dmrsSINR = double(rx.PostEqSINRDMRSResidual_dB);
decisionSINR = double(rx.PostEqDecisionResidual_dB);
measuredSINR = double(rx.PostEqSINR_dB);
assert(all(isfinite([rawSINR, dmrsSINR, decisionSINR, measuredSINR])), ...
    "Rank-2 PUSCH must expose finite raw, DM-RS residual, decision-residual and bounded post-eq SINR.");
expectedBound = min([rawSINR, dmrsSINR, decisionSINR]);
assert(abs(measuredSINR - expectedBound) < 1e-8, ...
    "PUSCH post-eq SINR must equal the conservative receiver-residual bound, not an optimistic raw equalizer value.");
assert(logical(rx.PostEqSINRDMRSResidualBoundApplied) || rawSINR <= dmrsSINR, ...
    "PUSCH must disclose whether the DM-RS residual constrained the raw equalizer SINR.");
assert(logical(rx.DecodeAttempted) && logical(rx.ULSCHDecodeAvailable) && ...
    logical(rx.Ok) && ~logical(rx.CRCError), ...
    "The high-SNR full-rank rank-2 PUSCH fixture must pass the real UL-SCH decoder.");
assert(double(rx.ChannelEstimatePilotRECount) > 0 && ...
    isfinite(double(rx.ReceiverHestSINR_dB)), ...
    "Rank-2 PUSCH must expose finite DM-RS channel-estimate evidence.");
% Compare each measurement with an independent reference at its OWN plane.
% The pilot diagnostic is per receive branch; post-equalization combines 64
% branches. Requiring those two numbers to be within 6 dB masks array gain
% (and previously masked lost CDM metadata inflating estimated noise).
cleanGrid = nrOFDMDemodulate(tx.Carrier, rxClean);
noiseGrid = nrOFDMDemodulate(tx.Carrier, noise);
gridNoiseReference = mean(abs(noiseGrid(:)).^2);
gridPlaneSize = size(cleanGrid, 1) * size(cleanGrid, 2);
pilotCells = unique(mod(double(tx.DMRSIndices(:))-1, gridPlaneSize)+1);
cleanBranches = reshape(cleanGrid, gridPlaneSize, nRx);
pilotSamples = cleanBranches(pilotCells, :);
pilotReference = 10*log10(mean(abs(pilotSamples(:)).^2)/gridNoiseReference);
[Wreference, referenceStatus] = sixgr.phy.ul.puschCodebookProjectionMatrix( ...
    tx.PUSCH.NumLayers, tx.PUSCH.NumAntennaPorts, tx.PUSCH.TPMI, ...
    tx.PUSCH.TransformPrecoding);
assert(~isempty(Wreference), 'Codebook reference unavailable: %s', referenceStatus);
effectiveChannel = H * Wreference;
gram = effectiveChannel' * effectiveChannel;
assert(norm(gram-diag(diag(gram)), 'fro') < 1e-10, ...
    'The independent combining reference requires orthogonal layer channels.');
combiningReference = 10*log10(mean(real(diag(gram)))/gridNoiseReference);
fprintf('PUSCH_SINR_PLANES pilot=%g reference=%g raw_posteq=%g reference=%g noise=%g reference=%g\n', ...
    rx.ReceiverHestSINR_dB,pilotReference,rawSINR,combiningReference, ...
    rx.NoiseVar,gridNoiseReference);
assert(abs(double(rx.NoiseVar)/gridNoiseReference-1) < 0.25, ...
    'Receiver noise must agree with independently demodulated actual noise samples.');
assert(double(rx.ReceiverHestSINR_dB) > 10 && ...
    abs(double(rx.ReceiverHestSINR_dB)-pilotReference) < 1, ...
    'Pilot SINR must agree with actual clean DM-RS power per receive branch.');
assert(abs(rawSINR-combiningReference) < 1, ...
    'Post-equalization SINR must agree with the independent orthogonal-channel combining reference.');

% The coupled runtime trims/materializes its channel before calling the
% receiver and marks the resulting sample stream as aligned.  A zero-delay
% AWGN channel is still aligned even though its trim count is zero.  Do not
% run a second blind DM-RS acquisition on that already aligned waveform:
% multi-port DM-RS correlations can otherwise select a later OFDM-symbol
% replica and destructively shift the complete slot.
cfgAligned = sixgr.util.structSet(cfg, ...
    "lls6g.receiverSync.RuntimeWaveformSampleAligned", true);
cfgAligned = sixgr.util.structSet(cfgAligned, ...
    "lls6g.receiverSync.ChannelFilterDelay_samples", 0);
cfgAligned = sixgr.util.structSet(cfgAligned, ...
    "lls6g.receiverSync.ChannelTrimSamples", 0);
[rxAligned, ~] = sixgr.phy.ul.PUSCH_Rx(rxWaveform, cfgAligned, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "PUSCHIndices", tx.PUSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", noiseVarTime, ...
    "NoiseVarDomain", "time", ...
    "CodingLayout", tx.CodingLayout, ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", false);
assert(~logical(rxAligned.TimingEstimateUsed) && ...
    string(rxAligned.TimingEstimateSource) == ...
        "runtime_aligned_waveform_no_timing_reacquisition" && ...
    abs(double(rxAligned.AppliedTimingCorrection_samples)) < 1e-12, ...
    ['An already sample-aligned runtime waveform must not be blindly ' ...
     'reacquired merely because the physical channel delay is zero.']);
assert(logical(rxAligned.Ok) && ~logical(rxAligned.CRCError), ...
    ['The aligned rank-2 PUSCH fixture must preserve the real UL-SCH ' ...
     'decode when timing estimation is enabled at the public receiver API.']);

% Exercise the explicit reduced-observation component path independently of
% production scheduling. Production MU grants use a full-dimensional
% identity preprocessor; this probe confirms an explicitly supplied
% semi-unitary matrix is still applied consistently to the waveform and
% exact peer tensor without being mislabeled as full-observation IRC.
[Wlayer, projectionStatus] = sixgr.phy.ul.puschCodebookProjectionMatrix( ...
    tx.PUSCH.NumLayers, tx.PUSCH.NumAntennaPorts, tx.PUSCH.TPMI, ...
    tx.PUSCH.TransformPrecoding);
assert(~isempty(Wlayer), "PUSCH codebook projection fixture failed: %s", projectionStatus);
[receiveCombiner, ~] = qr(H * Wlayer, 0);
peerNullspace = null(receiveCombiner');
assert(~isempty(peerNullspace), ...
    "The 64-branch fixture must expose a nonempty peer-interference nullspace.");
peerSymbols = tx.Waveform(:, 1) .* sqrt(8);
peerContribution = peerSymbols * peerNullspace(:, 1).';
contributionTensor = reshape(peerContribution, size(peerContribution, 1), nRx, 1);
rxWaveformMU = rxClean + peerContribution + noise;
cfg.phy.pusch.equalizer = "IRC";
combinerDigest = sixgr.phy.mimo.MatrixContract.digest(receiveCombiner);
[rxMU, infoMU] = sixgr.phy.ul.PUSCH_Rx(rxWaveformMU, cfg, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "PUSCHIndices", tx.PUSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", noiseVarTime, ...
    "NoiseVarDomain", "time", ...
    "CodingLayout", tx.CodingLayout, ...
    "ReceiveCombiningMatrix", receiveCombiner, ...
    "ReceiveCombiningMatrixSHA256", combinerDigest, ...
    "InterferenceContributionTensor", contributionTensor, ...
    "InterferenceContributionSource", "controlled_mu_peer", ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true);
assert(logical(rxMU.MUMIMOReceiveCombinerApplied) && ...
    double(rxMU.MUMIMOReceiveCombinerInputBranches) == 64 && ...
    double(rxMU.MUMIMOReceiveCombinerOutputBranches) == 2 && ...
    ~logical(rxMU.MUMIMOReceiveCombinerFullObservationPreserved) && ...
    string(rxMU.MUMIMOReceiveCombinerStatus) == ...
        "applied_explicit_semi_unitary_reduced_observation" && ...
    string(rxMU.MUMIMOReceiveCombinerMatrixSHA256) == string(combinerDigest), ...
    "The explicit component probe must report its exact 64-by-2 reduced observation.");
assert(logical(rxMU.MUMIMOReceiveCombinerInterferenceContributionProjected) && ...
    logical(rxMU.InterferenceCovarianceAvailable) && ...
    isfinite(double(rxMU.MeasuredInterferenceCovarianceTrace)) && ...
    double(rxMU.MeasuredInterferenceCovarianceTrace) > 0 && ...
    string(rxMU.InterferenceCovarianceSource) == ...
        "oracle_separated_shared_slot_per_prb_symbol_contribution_grid_covariance" && ...
    logical(infoMU.ReceiveCombiner.InterferenceContributionProjected), ...
    "PUSCH IRC must derive covariance from the peer tensor after the same receive projection.");
assert(logical(rxMU.Ok) && ~logical(rxMU.CRCError), ...
    "The high-SNR rank-2 UL MU fixture must pass after exact peer-null receive combining.");

fprintf("PUSCH rank-2 SINR: raw=%.3f dB dmrs=%.3f dB decision=%.3f dB bounded=%.3f dB Hest=%.3f dB.\n", ...
    rawSINR, dmrsSINR, decisionSINR, measuredSINR, double(rx.ReceiverHestSINR_dB));
ok = true;
end

function tf = localHaveRequired5G()
tf = exist("nrPUSCH", "file") == 2 && ...
    exist("nrPUSCHDecode", "file") == 2 && ...
    exist("nrChannelEstimate", "file") == 2 && ...
    exist("nrOFDMDemodulate", "file") == 2;
end
