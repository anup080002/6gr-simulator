function ok = testCSIMeasuredStateSchedulingSINRAuthority()
%TESTCSIMEASUREDSTATESCHEDULINGSINRAUTHORITY Keep one causal CSI objective.

setup6GRSimToolkit("Verbose", false);

cfg = sixgr.config.defaultConfig();
cfg.phy.nTxAnt = 2;
cfg.phy.nRxAnt = 2;
cfg.phy.mimo.strict = false;
cfg.phy.csi.reportCSI = true;
cfg.phy.csi.reportCQI = true;
cfg.phy.csi.reportPMI = true;
cfg.phy.csi.reportRI = true;
cfg.phy.csi.maxRank = 2;
cfg.phy.pdsch.cqiTable = "table1";
cfg.phy.pdsch.mcsTable = "qam64_table1";

% This deliberately weak two-port measurement must not inherit the very
% strong PDSCH post-equalization SINR supplied below.  The measurement
% object is the immutable CSI-RS observation used for RI/PMI/CQI.
H = [0.20 + 0.01i, 0.02; 0.01, 0.12 - 0.01i];
nVar = 0.10;
measurement = sixgr.phy.mimo.CSIMeasurementState( ...
    MeasurementID="CSI-AUTHORITY-1", UEID="1", ...
    ResourceType="CSI-RS", ResourceID="0", ResourceOrdinal=0, ...
    Slot=3, MaxAgeSlots=8, ChannelEstimate=H, ...
    NoiseVariance=nVar, Provenance="measured_csirs_unit_test");

[csi, info] = sixgr.phy.dl.CSI_Feedback(H, nVar, cfg, ...
    "Direction", "DL", "MeasurementState", measurement, ...
    "MaxRank", 2, "PostEqSINR_dB", 30, ...
    "PostEqSINRSource", "older_pdsch_dmrs_equalizer", ...
    "PostEqSINRValueRole", "measured_post_equalization_scheduling_input", ...
    "PostEqSINRValueStatus", "OK");

assert(strcmp(string(csi.SINRSource), ...
    "measured_csi_state_receiver_objective"), ...
    "A measured CSI-RS state must own the CQI scheduling objective.");
assert(isfinite(double(csi.ModelEffectiveSINR_dB)) && ...
    abs(double(csi.SINR_dB) - double(csi.ModelEffectiveSINR_dB)) < 1e-12, ...
    "CQI SINR must equal the codebook/equalizer objective from the same CSI state.");
assert(abs(double(csi.SINR_dB) - 30) > 1, ...
    "An older PDSCH DM-RS SINR must not override a current CSI-RS report.");
assert(~isfinite(double(csi.CQI)) && ...
    double(info.CQIFeedback.WidebandEffectiveSINR_dB) < ...
        double(info.CQIFeedback.SINRThresholds_dB(1)), ...
    char("The weak measured channel must produce the standards-defined " + ...
     "out-of-range CQI 0 internally and an unavailable public CQI, not CQI 15."));

% Without a measured CSI state, scheduler-eligible PDSCH post-EQ SINR is a
% permitted bootstrap/fallback source and remains explicitly labelled.
fallback = sixgr.phy.dl.CSI_Feedback(H, nVar, cfg, ...
    "Direction", "DL", "PostEqSINR_dB", 12, ...
    "PostEqSINRSource", "pdsch_dmrs_bootstrap", ...
    "PostEqSINRValueRole", "measured_post_equalization_scheduling_input", ...
    "PostEqSINRValueStatus", "OK");
assert(double(fallback.SINR_dB) == 12 && ...
    strcmp(string(fallback.SINRSource), "pdsch_dmrs_bootstrap"), ...
    "PDSCH bootstrap SINR must remain available only without CSI-RS state.");

ok = true;
end
