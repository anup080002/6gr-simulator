function ok=testDLBootstrapRankCapability()
% Config/policy regression, not proof of decoded multi-layer PDSCH.
% Bootstrap rank and the installed adaptation ceiling are separate inputs.
setup6GRSimToolkit('Verbose',false);
source=sixgr.lls6g.config.loadScenarioConfig(fullfile('simulator','configs', ...
    'scenarios','lls_tdd_5mhz_four_port_shared_awgn_12db.yaml'));
cfg=sixgr.lls6g.buildInternalConfig(source,tempname);
initial=double(source.get('pdsch.layer_count'));
ceiling=double(source.get('mimo.max_dl_layers'));
assert(initial<ceiling,'test:DLRankStimulus', ...
    'This regression requires a bootstrap rank below the configured ceiling.');
fprintf('DL_BOOTSTRAP_RANK_BASELINE initial=%g YAML_ceiling=%g runtime_ceiling=%g\n', ...
    initial,ceiling,cfg.phy.pdsch.maxLayers);
assert(cfg.phy.pdsch.numLayers==initial && cfg.phy.pdsch.nLayers==initial, ...
    'test:DLBootstrapRankChanged','Installing capability must not force the bootstrap transmission to that rank.');
assert(cfg.phy.pdsch.maxLayers==ceiling && cfg.phy.maxDLLayers==ceiling, ...
    'test:DLBootstrapRankCapability', ...
    'DL maximum capability was overwritten by the bootstrap rank.');
selected=sixgr.mimo.resolveRankExecutionPolicy(cfg,'DL',ceiling);
assert(selected.AdaptiveRank && selected.MaxSupportedLayers==ceiling && ...
    selected.EffectiveRank==ceiling && ~selected.DowngradeApplied, ...
    'test:DLRankCapabilityPolicy','A received rank within installed capability must remain executable.');
above=sixgr.mimo.resolveRankExecutionPolicy(cfg,'DL',ceiling+1);
assert(above.EffectiveRank==ceiling && above.DowngradeApplied, ...
    'test:DLRankCapabilityCeiling','A measured rank must not bypass the configured ceiling.');

% A received CSI report may select the installed rank on a future grant.
% The same report must not retrospectively rewrite an already finalized
% grant/TB spatial contract.
feedback=struct('Valid',true,'CQI',10,'RI',ceiling,'PMI',0, ...
    'SourceSlot',3,'DeliveredSlot',4);
future=struct('Slot',5,'RNTI',4101,'MCSIndex',0,'MCS',0, ...
    'PRBSet',0:24,'SymbolAllocation',[2 12]);
future=sixgr.truth.CoupledTruthRuntime.applyMeasuredFeedbackAMCToGrantRuntime( ...
    future,feedback,[],cfg,'DL');
assert(future.NumLayers==ceiling && future.RIUsed==ceiling && ...
    future.Rank==ceiling && future.PrecodingNumLayers==ceiling, ...
    'test:DLFutureGrantRank', ...
    'Received CSI RI within capability must control the next unfinalized DL grant.');

issued=struct('Slot',4,'RNTI',4101,'MCSIndex',0,'MCS',0, ...
    'PRBSet',0:24,'SymbolAllocation',[2 12], ...
    'ExactPHYFeasibilityChecked',true,'NumLayers',initial, ...
    'Layers',initial,'RIUsed',initial,'Rank',initial, ...
    'PrecodingNumLayers',initial);
issued=sixgr.truth.CoupledTruthRuntime.applyMeasuredFeedbackAMCToGrantRuntime( ...
    issued,feedback,[],cfg,'DL');
assert(issued.NumLayers==initial && issued.RIUsed==initial && ...
    issued.Rank==initial && issued.PrecodingNumLayers==initial && ...
    string(issued.RankAuthority)=="finalized_grant_spatial_contract" && ...
    string(issued.RankDecisionReason)=="measured_ri_deferred_to_future_grant", ...
    'test:DLFinalizedGrantRankMutation', ...
    'Received CSI must not rewrite the spatial contract of an issued DL grant.');
fprintf(['DL_BOOTSTRAP_RANK_CAPABILITY_PASS initial=%g maximum=%g ' ...
    'future_rank=%g finalized_rank=%g\n'],initial,ceiling,future.NumLayers,issued.NumLayers);
ok=true;
end
