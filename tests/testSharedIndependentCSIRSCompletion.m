function ok = testSharedIndependentCSIRSCompletion()
%TESTSHAREDINDEPENDENTCSIRSCOMPLETION Receive CSI-RS without PDSCH/DCI.

setup6GRSimToolkit("Verbose",false);
scenario=sixgr.lls6g.config.loadScenarioConfig( ...
    "simulator/configs/scenarios/lls_tdd_5mhz_rank2_4tx2rx_awgn_m10db.yaml");
cfg=sixgr.lls6g.buildInternalConfig(scenario,tempname);
cfg.phy.ssb.enable=false;
cfg.phy.sib1.enable=false;
cfg.phy.trs.enable=false;
cfg.phy.csirs.period_slots=1;
cfg.phy.csirs.offset_slots=0;
cfg.outputs.saveCSV=false;
cfg.outputs.saveMAT=false;
cfg.outputs.saveFigures=false;
runFolder=tempname;
mkdir(runFolder);
cfg.run.rootRunFolder=runFolder;

multi=struct("Enabled",true,"NumUsers",1,"RNTIStart",1, ...
    "ExecutionModel","slot_coupled_truth");
state=sixgr.truth.CoupledTruthRuntime.initialize(cfg,runFolder,multi,struct(),1);
state=sixgr.truth.CoupledTruthRuntime.startSlot( ...
    state,cfg,"DL",1,1,1,-10,12);
state.CurrentServingIdx(:)=1;
[state,owner]=sixgr.truth.CoupledWaveformStream.initialize(state,cfg,{cfg});
[cfgUE,~]=sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg,state,1,"DL");
cfgOwner=sixgr.util.structSet(cfgUE, ...
    "lls6g.runtime.independentCellCommonCSIRSOwner",true);
cfgOwner=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfgOwner,1,1);
grant=sixgr.link.resolveWaveformGrant( ...
    cfgOwner,"DL",1,"Slot",1,"SFN",0,"ControlAbsoluteSlot",0);
allocated=state.DLHarq.allocate(grant.RNTI,1,grant.TBSBytes,"NewData",true);
grant=sixgr.link.resolveWaveformGrant(cfgOwner,"DL",1,"Slot",1,"SFN",0, ...
    "ControlAbsoluteSlot",0,"HARQProcess",allocated.HARQ.HarqID);
grant.ControlDecodeOk=false;
grant.PDCCHGrantBindingOk=false;
job=sixgr.truth.buildGrantPHYJob(cfgOwner,"DL",-10,1,[], ...
    struct("GrantSnapshot",grant,"PHYGrant",grant.PHYGrant,"PrepareOnly",true));
job.StartSlotIndex=1;
dataPreparation=sixgr.truth.executeGrantPHYJob(job);
dataTx=dataPreparation.Result.PreparedTransmission.Tx;
dataEvent=dataTx.CSIRSRuntimeEvent;
assert(dataEvent.Scheduled && ~dataEvent.Transmitted && ...
    string(dataEvent.CellCommonSignalOwnershipMode)=="reserve_only" && ...
    startsWith(string(dataEvent.RuntimeMaterializationStatus), ...
        "reserved_only_"), ...
    ["Shared PDSCH must reserve configured CSI-RS REs while the " + ...
     "independent cell-common producer owns their physical emission. " + ...
     "scheduled=%d transmitted=%d mode=%s status=%s"], ...
    dataEvent.Scheduled,dataEvent.Transmitted, ...
    string(dataEvent.CellCommonSignalOwnershipMode), ...
    string(dataEvent.RuntimeMaterializationStatus));
[state,queued,queueReason,prepared]=sixgr.truth.queueSharedPeriodicCSIRS( ...
    state,cfgUE,1,1,1,1,1,-10);
assert(queued && queueReason== ...
    "configured_periodic_csirs_queued_on_shared_physical_stream" && ...
    owner.hasPending("CSIRS",1), ...
    "The production periodic scheduler boundary must enqueue CSI-RS.");
[state,completed]=owner.advanceSlot(state,cfg,@localReceive);

assert(numel(completed)==1 && completed.Kind=="CSIRS", ...
    "The independent CSI-RS observation must complete in its source slot.");
trial=state.ControlTrials.CSIRS;
assert(height(trial)==1 && trial.Slot==1 && trial.UEIndex==1 && ...
    trial.Scheduled && trial.Transmitted && trial.Observed && trial.Consumed, ...
    "The shared receiver must publish one actual completed CSI-RS row.");
assert(trial.ResourceExtractionAvailable && trial.ChannelEstimateAvailable && ...
    trial.CSIMeasurementAvailable && isfinite(trial.CQI) && ...
    isfinite(trial.RI) && isfinite(trial.PMI), ...
    "Independent reception must produce measured channel and CSI fields.");
% Compare with executed receiver-segment metadata, not a copied YAML axis.
executed=state.TestCSIRSExecutedNoiseEvidence;
noiseFields=["AppliedAWGNSNR_dB","ReferenceAWGNGridNoiseVariance", ...
    "ReferenceAWGNSampleNoiseVariance","SignalEnergyPerOccupiedRE"];
assert(all(ismember(noiseFields,string(trial.Properties.VariableNames))), ...
    'test:IndependentCSIRSExecutedNoiseExportMissing', ...
    'CSI-RS exports must retain the actual shared receiver noise authority.');
for name=noiseFields
    assert(isfield(executed,name) && isfinite(executed.(name)) && ...
        trial.(name)==executed.(name), ...
        'test:IndependentCSIRSExecutedNoiseMismatch', ...
        'CSI-RS field %s must equal its executed physical observation.',name);
end
assert(trial.ConfiguredSNR_dB==prepared.RequestedSNR_dB && ...
    trial.ConfiguredSNR_dB==trial.AppliedAWGNSNR_dB, ...
    'test:IndependentCSIRSSNRBinding', ...
    'The fixed-AWGN trial must bind requested and actually applied SNR.');
expectedGridNoise=executed.SignalEnergyPerOccupiedRE* ...
    10^(-executed.AppliedAWGNSNR_dB/10);
assert(abs(trial.ReferenceAWGNGridNoiseVariance-expectedGridNoise) <= ...
    1e-12*max(1,expectedGridNoise), ...
    'test:IndependentCSIRSNoiseCalibration', ...
    'Exported occupied-RE noise must agree with executed reference energy and SNR.');
assert(isfinite(trial.SINR_dB) && trial.SINRValueStatus=="OK" && ...
    strlength(trial.SINRValueDefinition)>0 && ...
    ~contains(lower(trial.SINRValueDefinition),["no_control_sinr","unavailable"]), ...
    'test:IndependentCSIRSMeasurementContradiction', ...
    'A measured CSI receiver objective cannot be described as no observation.');
assert(trial.ReferenceMeasuredSINRDomain== ...
    "csi_rs_port3000_reference_re_received_plane" && ...
    trial.SINRValueRole=="measured_csi_receiver_objective_scheduling_input", ...
    'test:IndependentCSIRSSINRDomainConflation', ...
    'Reference-RE SINR and the scheduling objective must remain distinct quantities.');
assert(trial.MeasuredTrialSINR_dB==trial.ReferenceMeasuredSINR_dB && ...
    trial.MeasuredSINR_dB==trial.ReferenceMeasuredSINR_dB && ...
    trial.MeasuredTrialSINRMeasurementDomain==trial.ReferenceMeasuredSINRDomain && ...
    contains(trial.SINRValueDefinition,"receiver_objective"), ...
    'test:IndependentCSIRSReferencePublicationNotIntegrated', ...
    ['Publish the actual reference measurement through the canonical reader fields; ' ...
     'the distinct selected-PMI scheduling objective keeps its own definition.']);
% Configured SNR cannot fill absent physical execution evidence.
withoutExecution=state.TestCSIRSReception;
withoutExecution=rmfield(withoutExecution,'NoiseExecutionEvidence');
missingRow=sixgr.truth.buildIndependentCSIRSTrialRow( ...
    prepared.ReceiverConfig,prepared,withoutExecution,state.TestCSIRSReport, ...
    state.TestCSIRSContext);
for name=noiseFields
    assert(isnan(missingRow.(name)), ...
        'test:IndependentCSIRSNoiseEvidenceFabricated', ...
        'Absent executed %s must not be reconstructed from the requested SNR.',name);
end
assert(missingRow.SINR_dB==trial.SINR_dB && ...
    missingRow.MeasuredTrialSINR_dB==trial.MeasuredTrialSINR_dB, ...
    'test:IndependentCSIRSNoiseMetadataChangedMeasurement', ...
    'Removing audit noise metadata must not change receiver measurements.');
assert(trial.SINRMeasurementDomain=="selected_precoder_layer_receiver_objective" && ...
    trial.SINRMeasurementDomain~=trial.MeasuredTrialSINRMeasurementDomain);
csv=fullfile(runFolder,'independent_csirs_receiver.csv');
writetable(trial,csv);
persisted=readtable(csv,'TextType','string','VariableNamingRule','preserve', ...
    'Delimiter',',','ReadVariableNames',true,'NumHeaderLines',0);
for name=[noiseFields,"ConfiguredSNR_dB","MeasuredTrialSINR_dB","SINR_dB"]
    assert(abs(persisted.(name)-trial.(name))<=1e-12*max(1,abs(trial.(name))), ...
        'Actual receiver/calibration field %s must survive CSV export.',name);
end
assert(persisted.SINRMeasurementDomain==trial.SINRMeasurementDomain && ...
    persisted.MeasuredTrialSINRMeasurementDomain==trial.MeasuredTrialSINRMeasurementDomain);
assert(trial.ResultAvailableAtSample==trial.ObservationEndSampleExclusive && ...
    trial.ObservationStartSample==0 && trial.ObservationSampleRateHz==owner.SampleRateHz, ...
    "CSI publication must retain the actual shared receiver completion clock.");
assert(string(trial.RuntimeTransportMode)== ...
    "shared_physical_stream_independent_CSIRS_received_completion" && ...
    ~contains(lower(string(trial.MeasurementSource)),["proxy","fallback","synthetic"]), ...
    "Primary CSI evidence must remain actual shared-stream receiver evidence.");
assert(isempty(owner.Pending) && isempty(owner.DataTransmissions), ...
    "The focused measurement must not require or fabricate PDSCH/DCI/HARQ.");
assert(numel(owner.CSIRSTransmissions)==1 && ...
    owner.CSIRSTransmissions.Slot==1 && ...
    owner.CSIRSTransmissions.EndSampleExclusive<=owner.Events.NextSampleIndex, ...
    "The physical owner must retain one completed cell-common CSI-RS TX record.");
referenceCalendar=table(1,'VariableNames',{'CSIReferenceSlot'});
[eligible,referenceEvidence]=sixgr.truth.resolveCSIReceiveReferenceEvidence( ...
    state,cfgUE,1,1,referenceCalendar,4);
assert(eligible && height(referenceEvidence)==1 && ...
    referenceEvidence.Slot==1 && isnan(referenceEvidence.EmbeddingUEIndex) && ...
    referenceEvidence.Source== ...
    "gnb_completed_independent_csirs_TX_not_UE_measurement_outcome", ...
    ["The independently scheduled gNB receiver must bind the completed " + ...
     "cell-common CSI-RS TX ledger, not the obsolete PDSCH-embedded ledger."]);
receiveCfg=cfgUE;
receiveCfg.phy.csi.reportPeriodicitySlots=5;
receiveCfg.phy.csi.reportOffsetSlots=4;
hypothesis=sixgr.truth.buildConfiguredPUCCHCSIReception( ...
    state,receiveCfg,1,5,"focused_independent_csirs_report_slot_5");
assert(hypothesis.SelectedTransport=="PUCCH" && ...
    height(hypothesis.CSIReferenceTransmissionEvidence)==1 && ...
    hypothesis.CSIReferenceTransmissionEvidence.Slot==1, ...
    "The production CSI-only gNB hypothesis must consume the physical CSI-RS TX ledger.");
assert(~isempty(state.ObservedREAllocationTable) && ...
    any(string(state.ObservedREAllocationTable.channel)=="CSI-RS"), ...
    "Actual independent CSI-RS RE ownership must be retained for exports.");
fprintf(["SHARED_INDEPENDENT_CSIRS_COMPLETION_PASS CQI=%g RI=%g PMI=%g " + ...
    "SINR=%g available_sample=%g\n"],trial.CQI,trial.RI,trial.PMI, ...
    trial.SINR_dB,trial.ResultAvailableAtSample);
ok=true;
end

function state=localReceive(state,items)
for item=reshape(items,1,[])
    assert(item.Kind=="CSIRS", ...
        "The focused source slot must complete only CSI-RS.");
    [~,~,~,executed]=sixgr.truth.sharedObservationEvidence( ...
        item.Planes,item.Context.Prepared);
    state.TestCSIRSExecutedNoiseEvidence=executed;
    [state,~,reception,csi]=sixgr.truth.completeSharedCSIRSReception(state,item);
    state.TestCSIRSReception=reception;
    state.TestCSIRSReport=csi;
    state.TestCSIRSContext=item.Context;
    p=item.Context.Prepared;
    observed=sixgr.truth.buildObservedREAllocation(p.Tx, ...
        "Direction","DL","Channel","CSI-RS", ...
        "AbsoluteSlot",item.Context.Slot-1,"CellID",item.Context.ServingCell, ...
        "UEID",NaN,"AllocationID","csirs_cell_1_slot_0");
    state.ObservedREAllocationTable=localAppend( ...
        sixgr.util.structGet(state,"ObservedREAllocationTable",table()),observed);
end
end

function out=localAppend(out,rows)
if isempty(out)
    out=rows;
    return;
end
if isempty(rows)
    return;
end
missing=setdiff(out.Properties.VariableNames,rows.Properties.VariableNames,"stable");
for name=string(missing)
    rows.(name)=out.(name)(1+zeros(height(rows),1),:);
end
missing=setdiff(rows.Properties.VariableNames,out.Properties.VariableNames,"stable");
for name=string(missing)
    out.(name)=rows.(name)(1+zeros(height(out),1),:);
end
rows=rows(:,out.Properties.VariableNames);
out=[out;rows];
end
