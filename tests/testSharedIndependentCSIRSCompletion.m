function ok = testSharedIndependentCSIRSCompletion(timingGuard,receiverDelay)
%TESTSHAREDINDEPENDENTCSIRSCOMPLETION Receive CSI-RS without PDSCH/DCI.
if nargin<1, timingGuard=0; end
if nargin<2, receiverDelay=0; end
pointSNR=-10;
if receiverDelay>0, pointSNR=30; end

setup6GRSimToolkit("Verbose",false);
schema=sixgr.truth.emptyCSIRSTrialTable();
assert(height(schema)==0 && isstring(schema.Direction) && ...
    isstring(schema.ReceiverWindowID) && ...
    isstring(schema.PhysicalMeasurementSynchronizationJSON) && ...
    islogical(schema.Observed) && isnumeric(schema.Slot), ...
    'The empty canonical schema must retain types without manufacturing a row.');
scenario=sixgr.lls6g.config.loadScenarioConfig( ...
    "simulator/configs/scenarios/lls_tdd_5mhz_rank2_4tx2rx_awgn_m10db.yaml");
% Exercise the generic configured audit on the existing bounded physical
% regression; this is not a new 5-MHz campaign or a full n40 qualification.
scenario=scenario.toStruct();
scenario.kpi_spec.csi_selection_quality.enabled=true;
% The installed resource-set vector is authoritative even for one resource.
% Changing only a legacy scalar after build does not install resource 17.
scenario.reference_signals.csi_rs_resource_ids=17;
cfg=sixgr.lls6g.buildInternalConfig(scenario,tempname);
assert(cfg.channel.awgnBeamFailureRecoveryEnabled && ...
    string(cfg.phy.csirs.runtimeChannelEstimator)=="nr_channel_estimate" && ...
    string(cfg.phy.trs.runtimeChannelEstimator)=="nr_channel_estimate" && ...
    string(cfg.phy.srs.runtimeChannelEstimator)=="nr_channel_estimate", ...
    'test:PiecewiseRSEstimatorConfiguration', ...
    'The production piecewise-channel scenario must select native per-resource RS estimators.');
cfg=sixgr.truth.bindStandaloneSNRPoint(cfg,pointSNR);
cfg.phy.ssb.enable=false;
cfg.phy.sib1.enable=false;
cfg.phy.trs.enable=false;
cfg.phy.csirs.period_slots=1;
cfg.phy.csirs.offset_slots=0;
cfg.phy.csirs.resourceID=17; % Keep the legacy singleton alias consistent.
assert(isequal(cfg.phy.csirs.resourceIDs,17));
cfg.phy.synchronization=struct('maxTimingUncertaintySamples',timingGuard);
if receiverDelay>0
    cfg.rf.rx.enable=true;
    cfg.rf.rx.timingOffsetSamples=receiverDelay;
    % Keep the production scenario's native per-resource estimator for
    % this added RF delay too; do not override its estimator policy here.
end
cfg.outputs.saveCSV=false;
cfg.outputs.saveMAT=false;
cfg.outputs.saveFigures=false;
cfg.outputs.rawIQCaptureEnabled=true;
cfg.outputs.saveRawWaveforms=true;
runFolder=tempname;
mkdir(runFolder);
cfg.run.rootRunFolder=runFolder;
cfg.run.runTag="shared_independent_csirs_population";

multi=struct("Enabled",true,"NumUsers",1,"RNTIStart",1, ...
    "ExecutionModel","slot_coupled_truth");
% Production initializes this owner with a component folder, not the run
% root. Storage references must still resolve identically from both CSVs.
componentFolder=fullfile(runFolder,'air_interface');
state=sixgr.truth.CoupledTruthRuntime.initialize(cfg,componentFolder,multi,struct(),1);
state=sixgr.truth.CoupledTruthRuntime.startSlot( ...
    state,cfg,"DL",1,1,1,pointSNR,12);
state.CurrentServingIdx(:)=1;
state.CurrentSweepPointIndex=3;
[state,owner]=sixgr.truth.CoupledWaveformStream.initialize(state,cfg,{cfg});
[cfgUE,~]=sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg,state,1,"DL");
cfgOwner=sixgr.util.structSet(cfgUE, ...
    "lls6g.runtime.independentCellCommonCSIRSOwner",true);
cfgOwner=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfgOwner,1,1);
grant=sixgr.link.resolveWaveformGrant( ...
    cfgOwner,"DL",1,"Slot",1,"SFN",0,"ControlAbsoluteSlot",0);
allocated=state.DLHarq.allocate(grant.RNTI,1,grant.TBSBytes,"NewData",true);
grant=sixgr.link.resolveWaveformGrant(cfgOwner,"DL",1,"Slot",1,"SFN",0, ...
    "ControlAbsoluteSlot",0,"HARQProcess",allocated.HARQ.HarqID);
grant.ControlDecodeOk=false;
grant.PDCCHGrantBindingOk=false;
job=sixgr.truth.buildGrantPHYJob(cfgOwner,"DL",pointSNR,1,[], ...
    struct("GrantSnapshot",grant,"PHYGrant",grant.PHYGrant,"PrepareOnly",true));
job.StartSlotIndex=1;
dataPreparation=sixgr.truth.executeGrantPHYJob(job);
dataTx=dataPreparation.Result.PreparedTransmission.Tx;
dataEvent=dataTx.CSIRSRuntimeEvent;
assert(dataEvent.Scheduled && ~dataEvent.Transmitted && ...
    string(dataEvent.CellCommonSignalOwnershipMode)=="reserve_only" && ...
    startsWith(string(dataEvent.RuntimeMaterializationStatus), ...
        "reserved_only_"), ...
    ["Shared PDSCH must reserve configured CSI-RS REs while the " + ...
     "independent cell-common producer owns their physical emission. " + ...
     "scheduled=%d transmitted=%d mode=%s status=%s"], ...
    dataEvent.Scheduled,dataEvent.Transmitted, ...
    string(dataEvent.CellCommonSignalOwnershipMode), ...
    string(dataEvent.RuntimeMaterializationStatus));
[state,queued,queueReason,prepared]=sixgr.truth.queueSharedPeriodicCSIRS( ...
    state,cfgUE,1,1,1,1,1,pointSNR);
assert(queued && queueReason== ...
    "configured_periodic_csirs_queued_on_shared_physical_stream" && ...
    owner.hasPending("CSIRS",1), ...
    "The production periodic scheduler boundary must enqueue CSI-RS.");
queuedCSI=owner.Pending(string({owner.Pending.Kind})=="CSIRS");
queuedPopulation=queuedCSI.Context.PopulationIdentity;
% Delayed completion must not be relabelled with the current sweep point.
state.CurrentSweepPointIndex=9;
[state,completed]=owner.advanceSlot(state,cfg,@localReceive);
if timingGuard>0
    assert(isempty(completed) && owner.hasPending("CSIRS",1), ...
        'CSI-RS cannot complete before the configured actual receive tail.');
    queuedCSI=owner.Pending(string({owner.Pending.Kind})=="CSIRS");
    actualTX=queuedCSI.Context.Prepared;
    assert(numel(owner.CSIRSTransmissions)==1 && ...
        owner.CSIRSTransmissions.CommittedAtSample==actualTX.TransmitStartSample+actualTX.NumSamples && ...
        owner.CSIRSTransmissions.CommittedAtSample==owner.Events.NextSampleIndex, ...
        'The actual gNB CSI-RS TX must be committed before the longer UE receive window completes.');
    [txEligible,txEvidence]=sixgr.truth.resolveCSIReceiveReferenceEvidence( ...
        state,cfgUE,1,1,table(1,'VariableNames',{'CSIReferenceSlot'}),4);
    assert(txEligible && height(txEvidence)==1, ...
        'gNB CSI receive applicability must not depend on a future UE measurement outcome.');
    state.CurrentSlot=2;
    [state,completed]=owner.advanceSlot(state,cfg,@localReceive);
end
assert(numel(completed)==1 && completed.Kind=="CSIRS", ...
    "The independent CSI-RS observation must complete on its actual RX clock.");
trial=state.ControlTrials.CSIRS;
assert(trial.SweepPointIndex==3 && trial.ConfiguredSNR_dB==pointSNR && ...
    trial.RunTag==cfg.run.runTag && trial.ConfigHash==queuedPopulation.Fields.ConfigHash && ...
    trial.CSIObservationPopulationSHA256==queuedPopulation.SHA256, ...
    'test:CSIObservationPopulationChanged','Completion must retain the actual queued population.');
assert(trial.ResourceID==17 && trial.CRI==0 && ...
    state.TestCSIRSReception.CSIMeasurementState.ResourceID=="CSI-RS-17" && ...
    state.TestCSIRSReception.CSIMeasurementState.ResourceOrdinal==0, ...
    'test:CSISingletonIdentity','An arbitrary singleton resource ID must not become CRI.');
assert(trial.CSISelectionQualityAvailable && ...
    ~trial.CSISelectionQualityStatisticallyQualified && ...
    ~trial.CSISelectionQualityActualPDSCHPerformanceQualified && ...
    trial.CSISelectionQualitySupportCount>0 && trial.CSISelectionQualityCandidateCount>0, ...
    'test:CSISelectionNotIntegrated','Actual shared CSI completion must publish the enabled private selection audit.');
quality=load(fullfile(runFolder,trial.CSISelectionQualityMATFile));
assert(quality.Identity.SweepPointIndex==3 && ...
    quality.Identity.CSIObservationPopulationSHA256==queuedPopulation.SHA256 && ...
    quality.Inputs.Reference.CSIObservationPopulationJSON==string(jsonencode(queuedPopulation)) && ...
    quality.Inputs.Reference.CSIObservationPopulationBindingJSON==trial.CSIObservationPopulationBindingJSON && ...
    quality.Inputs.Reference.CSIObservationPopulationJSONSHA256== ...
        sixgr.util.sha256Hex(char(trial.CSIObservationPopulationJSON)), ...
    'test:CSIObservationArchivePopulation','Immutable archive must retain the queue and actual TX-receipt binding.');
assert(quality.Identity.MeasurementID==trial.CSIMeasurementID && ...
    quality.Identity.ReceiverWindowID==trial.ReceiverWindowID && ...
    trial.ReceiverWindowID==completed.ID && ...
    quality.Identity.ObservationSHA256==trial.ReceiverObservationSHA256 && ...
    quality.Summary.SelectedRank==trial.RI && quality.Summary.SelectedPMI==trial.PMI && ...
    isequaln(quality.Inputs.Selection.Precoder_W,state.TestCSIRSReport.Precoder_W) && ...
    quality.Inputs.Disturbance.NoiseReceipt.AdditionalNoiseExecutions==0 && ...
    quality.Inputs.Reference.SupportScope=="selected_resource_pilot_union" && ...
    quality.Inputs.Policy.PhysicalPowerUnit=="normalized_grid_coefficient_squared_units", ...
    'test:CSISelectionWrongPopulation','Audit must retain this actual UE recommendation/FFT/noise population.');
meta=struct('logical_run_id',"bounded_physical_CSI_selection_integration",'run_id',1);
public=sixgr.truth.buildLLSPublicOutputTables(struct('csi_rs_table',trial),sixgr.truth.llsOutputContract(),meta);
assert(public.csi_rs_runtime_event_table.CSISelectionQualityMATFile==trial.CSISelectionQualityMATFile && ...
    public.csi_rs_runtime_event_table.SweepPointIndex==3 && ...
    public.csi_rs_runtime_event_table.CSIObservationPopulationSHA256==queuedPopulation.SHA256 && ...
    public.csi_rs_runtime_event_table.ReceiverWindowID==completed.ID && ...
    public.csi_rs_runtime_event_table.CSISelectionQualityJointRegret_bpsHz==trial.CSISelectionQualityJointRegret_bpsHz && ...
    isempty(public.csi_report_table), ...
    'test:CSISelectionPublicScope','Private UE scoring must survive publication without becoming received UCI.');
assert(trial.RuntimeStageWaveformsUsed && ...
    trial.ReceiverObservationHashPlane=="actual_receiver_input_before_synchronization");
for prefix=["Receiver","PhysicalMeasurement"]
    receipt=jsondecode(trial.(prefix+"ObservationArchiveReceiptJSON"));
    archived=sixgr.phy.waveform.CompletedSampleArchive.read(receipt);
    assert(isequaln(archived,state.("TestCSIRS"+prefix+"Samples")) && ...
        string(receipt.RelativePath)==trial.(prefix+"ObservationArchiveFile") && ...
        string(receipt.FileSHA256)==trial.(prefix+"ObservationArchiveFileSHA256") && ...
        string(receipt.Manifest.SampleSHA256)==trial.(prefix+"ObservationSHA256"), ...
        'test:CSIRSReceivedCaptureNotRetained', ...
        'Full receiver input and pre-front-end samples must round-trip exactly, independently of EVM pairs.');
end
assert(ismember('NMSEScoringAvailable',trial.Properties.VariableNames) && ...
    trial.NMSEScoringAvailable && isfinite(trial.NMSE_dB) && ...
    trial.ChannelNMSEComparedComplexValues>0 && ...
    ~trial.ChannelNMSEReferenceUsedByReceiver, ...
    'test:MissingIndependentCSIRSChannelScore', ...
    'The shared CSI-RS receiver must independently score its actual channel estimate after CSI selection.');
scored=sixgr.util.csvReadTable(fullfile(runFolder,trial.ChannelEstimateResourcesCSV),'TextType','string');
assert(height(scored)==trial.ChannelNMSEComparedComplexValues && ...
    strlength(trial.CSIChannelEstimateObservationID)>0 && ...
    all(scored.CSIChannelEstimateObservationID==trial.CSIChannelEstimateObservationID) && ...
    abs(sum(scored.ChannelErrorEnergy)-trial.ChannelNMSEErrorEnergy)<1e-9 && ...
    abs(sum(scored.ReferenceChannelEnergy)-trial.ChannelNMSEReferenceEnergy)<1e-9 && ...
    abs(10*log10(sum(scored.ChannelErrorEnergy)/sum(scored.ReferenceChannelEnergy))-trial.NMSE_dB)<1e-9, ...
    'test:CSIRSChannelScoreCSVClosure','Exact per-port paired operands must reproduce independent NMSE.');
for prefix=["Receiver","PhysicalMeasurement"]
    assert(trial.(prefix+"DemodulatedSampleCount")>0 && ...
        isfinite(trial.(prefix+"TimingCorrection_samples")) && ...
        trial.(prefix+"TimingSource")=="received_per_resource_noncoherent_correlation_bounded_search" && ...
        trial.(prefix+"SynchronizationSampleDomain")== ...
        "relative_to_observation_capture_start_zero_based" && ...
        strlength(trial.(prefix+"SynchronizationSource"))>0);
    sync=jsondecode(trial.(prefix+"SynchronizationJSON"));
    assert(sync.Timing.SearchWindowSamples(2)==timingGuard && ...
        sync.Timing.TimingSearchHypothesisCount==timingGuard+1 && ...
        sync.Timing.TimingAcquisitionPerformed==(timingGuard>0) && ...
        sync.Timing.ReferenceResourceEvidence.ResourceCount>=1 && ...
        string(sync.Timing.ReferenceResourceEvidence.Method)== ...
            "per_resource_noncoherent_received_reference_energy");
    assert(sync.Timing.AppliedTimingCorrectionSamples==trial.(prefix+"TimingCorrection_samples") && ...
        sync.Timing.DemodulatedSampleCount==trial.(prefix+"DemodulatedSampleCount") && ...
        ~sync.Timing.OracleTimingUsed && ~sync.Timing.ReceiverZeroPaddingUsed);
end
if receiverDelay>0
    assert(trial.ReceiverTimingCorrection_samples==receiverDelay && ...
        trial.PhysicalMeasurementTimingCorrection_samples==0, ...
        'Practical post-RF acquisition must recover RX delay independently of the pre-RF plane.');
end
assert(ismember('ControlEVMSamplesMATFile',trial.Properties.VariableNames) && ...
    strlength(trial.ControlEVMSamplesMATFile)>0 && ...
    strlength(trial.ControlEVMSamplesJSON)==0, ...
    'test:CSIInlineEVMRetention', ...
    'Retain full paired samples once in an immutable detail artifact, not every live CSI row.');
paired=sixgr.report.readControlEVMPairs(trial,fullfile(runFolder,'air_interface','csv','csi_rs_trials.csv'));
assert(isfile(fullfile(runFolder,trial.ControlEVMSamplesMATFile)), ...
    'test:CSIEVMWrongRoot','Paired CSI samples must be stored relative to cfg.run.rootRunFolder.');
mirrored=sixgr.report.readControlEVMPairs(trial,fullfile(runFolder,'control','csv','csi_rs_trials.csv'));
assert(isequaln(mirrored,paired),'Primary and mirrored trial CSVs must read the same retained samples.');
assert(sum(arrayfun(@(p)numel(p.SampleIndex),paired))==nnz(prepared.Tx.Grid), ...
    'Every actual emitted CSI-RS port/RE must remain available to the EVM writer.');
assert(height(trial)==1 && trial.Slot==1 && trial.UEIndex==1 && ...
    trial.Scheduled && trial.Transmitted && trial.Observed && trial.Consumed, ...
    "The shared receiver must publish one actual completed CSI-RS row.");
resourceEvidence=sixgr.truth.executedResourceIntervals(prepared.Tx.Grid,0);
for field=string(fieldnames(resourceEvidence)).'
    assert(isequaln(trial.(field),resourceEvidence.(field)), ...
        'Completed CSI-RS row lost actual resource interval evidence: %s',field);
end
assert(trial.ResourceExtractionAvailable && trial.ChannelEstimateAvailable && ...
    trial.CSIMeasurementAvailable && isfinite(trial.CQI) && ...
    isfinite(trial.RI) && isfinite(trial.PMI), ...
    "Independent reception must produce measured channel and CSI fields.");
assert(trial.PhysicalMeasurementStatus=="available_normalized_fixed_esn0_not_absolute_dbm" && ...
    isnan(trial.MeasurementRSRP_dBm) && isnan(trial.MeasurementRSSI_dBm) && ...
    isfinite(trial.MeasurementRSRP_dB_re_UnitOccupiedRE_Es) && ...
    isfinite(trial.MeasurementRSSI_dB_re_UnitOccupiedRE_Es), ...
    'The actual normalized shared capture must produce relative measurements, not invented dBm.');
referencePowers=jsondecode(trial.ReferenceSINRMeasurementJSON);
assert(string(referencePowers.PowerUnit)=="relative_to_unit_occupied_RE_Es");
assert(abs(trial.MeasurementRSRQ_dB-(10*log10(trial.MeasurementNumRB)+ ...
    trial.MeasurementRSRQNumeratorRSRP_dB_re_UnitOccupiedRE_Es- ...
    trial.MeasurementRSRQDenominatorRSSI_dB_re_UnitOccupiedRE_Es))<1e-9, ...
    'RSRQ must retain its own receive-branch numerator and denominator in the same power domain.');
assert(trial.SFN==mod(double(prepared.Carrier.NFrame),1024) && ...
    trial.Frame==prepared.Timeline.FrameIndexOneBased && ...
    trial.Slot==prepared.RuntimeSlot, ...
    'test:IndependentCSIRSExecutedClock', ...
    'CSI-RS SFN must use the executed carrier, separately from runtime Frame/Slot.');
% Compare with executed receiver-segment metadata, not a copied YAML axis.
executed=state.TestCSIRSExecutedNoiseEvidence;
noiseFields=["AppliedAWGNSNR_dB","ReferenceAWGNGridNoiseVariance", ...
    "ReferenceAWGNSampleNoiseVariance","SignalEnergyPerOccupiedRE"];
assert(all(ismember(noiseFields,string(trial.Properties.VariableNames))), ...
    'test:IndependentCSIRSExecutedNoiseExportMissing', ...
    'CSI-RS exports must retain the actual shared receiver noise authority.');
for name=noiseFields
    assert(isfield(executed,name) && isfinite(executed.(name)) && ...
        trial.(name)==executed.(name), ...
        'test:IndependentCSIRSExecutedNoiseMismatch', ...
        'CSI-RS field %s must equal its executed physical observation.',name);
end
assert(trial.ConfiguredSNR_dB==prepared.RequestedSNR_dB && ...
    trial.ConfiguredSNR_dB==trial.AppliedAWGNSNR_dB, ...
    'test:IndependentCSIRSSNRBinding', ...
    'The fixed-AWGN trial must bind requested and actually applied SNR.');
expectedGridNoise=executed.SignalEnergyPerOccupiedRE* ...
    10^(-executed.AppliedAWGNSNR_dB/10);
assert(abs(trial.ReferenceAWGNGridNoiseVariance-expectedGridNoise) <= ...
    1e-12*max(1,expectedGridNoise), ...
    'test:IndependentCSIRSNoiseCalibration', ...
    'Exported occupied-RE noise must agree with executed reference energy and SNR.');
assert(isfinite(trial.SINR_dB) && trial.SINRValueStatus=="OK" && ...
    strlength(trial.SINRValueDefinition)>0 && ...
    ~contains(lower(trial.SINRValueDefinition),["no_control_sinr","unavailable"]), ...
    'test:IndependentCSIRSMeasurementContradiction', ...
    'A measured CSI receiver objective cannot be described as no observation.');
assert(trial.ReferenceMeasuredSINRDomain== ...
    "csi_rs_port3000_reference_re_received_plane" && ...
    trial.SINRValueRole=="measured_csi_receiver_objective_scheduling_input", ...
    'test:IndependentCSIRSSINRDomainConflation', ...
    'Reference-RE SINR and the scheduling objective must remain distinct quantities.');
assert(trial.MeasuredTrialSINR_dB==trial.ReferenceMeasuredSINR_dB && ...
    trial.MeasuredSINR_dB==trial.ReferenceMeasuredSINR_dB && ...
    trial.MeasuredTrialSINRMeasurementDomain==trial.ReferenceMeasuredSINRDomain && ...
    contains(trial.SINRValueDefinition,"receiver_objective"), ...
    'test:IndependentCSIRSReferencePublicationNotIntegrated', ...
    ['Publish the actual reference measurement through the canonical reader fields; ' ...
     'the distinct selected-PMI scheduling objective keeps its own definition.']);
% Configured SNR cannot fill absent physical execution evidence.
withoutExecution=state.TestCSIRSReception;
withoutExecution=rmfield(withoutExecution,'NoiseExecutionEvidence');
missingRow=sixgr.truth.buildIndependentCSIRSTrialRow( ...
    prepared.ReceiverConfig,prepared,withoutExecution,state.TestCSIRSReport, ...
    state.TestCSIRSContext);
for name=noiseFields
    assert(isnan(missingRow.(name)), ...
        'test:IndependentCSIRSNoiseEvidenceFabricated', ...
        'Absent executed %s must not be reconstructed from the requested SNR.',name);
end
assert(missingRow.SINR_dB==trial.SINR_dB && ...
    missingRow.MeasuredTrialSINR_dB==trial.MeasuredTrialSINR_dB, ...
    'test:IndependentCSIRSNoiseMetadataChangedMeasurement', ...
    'Removing audit noise metadata must not change receiver measurements.');
syncFields=["PhysicalMeasurementReceiveTiming","PhysicalMeasurementTrackingCorrection", ...
    "PhysicalMeasurementSynchronizationSource"];
receiptFields=["PhysicalMeasurementDemodulationReceiptAvailable", ...
    "PhysicalMeasurementDemodulationReceiptStatus", ...
    "PhysicalMeasurementDemodulationReceiptJSON","PhysicalMeasurementDemodulationReceiptSHA256"];
% A retained receipt with an absent/malformed original source is an orphan,
% not a historical row with wholly absent synchronization evidence.
for name=syncFields
    orphan=rmfield(state.TestCSIRSReception,char(name));
    localReject(@()sixgr.truth.buildIndependentCSIRSTrialRow( ...
        prepared.ReceiverConfig,prepared,orphan,state.TestCSIRSReport,state.TestCSIRSContext), ...
        'sixgr:truth:CSIPhysicalDemodulationReceiptMismatch');
end
for mutation=1:5
    malformed=state.TestCSIRSReception;
    switch mutation
        case 1
            malformed.PhysicalMeasurementReceiveTiming= ...
                repmat(malformed.PhysicalMeasurementReceiveTiming,1,2);
        case 2
            malformed.PhysicalMeasurementTrackingCorrection= ...
                repmat(malformed.PhysicalMeasurementTrackingCorrection,1,2);
        case 3
            malformed.PhysicalMeasurementSynchronizationSource=["first" "second"];
        case 4
            malformed.PhysicalMeasurementReceiveTiming.InputSampleCount=[1 2];
        case 5
            malformed.PhysicalMeasurementTrackingCorrection.CFOCorrectionApplied=[false false];
    end
    localReject(@()sixgr.truth.buildIndependentCSIRSTrialRow( ...
        prepared.ReceiverConfig,prepared,malformed,state.TestCSIRSReport,state.TestCSIRSContext), ...
        'sixgr:truth:CSIPhysicalDemodulationReceiptMismatch');
end
withoutSync=rmfield(state.TestCSIRSReception,cellstr([syncFields receiptFields]));
missingSync=sixgr.truth.buildIndependentCSIRSTrialRow( ...
    prepared.ReceiverConfig,prepared,withoutSync,state.TestCSIRSReport,state.TestCSIRSContext);
assert(isnan(missingSync.PhysicalMeasurementEstimatedCFO_Hz) && ...
    isnan(missingSync.PhysicalMeasurementTimingCorrection_samples) && ...
    missingSync.PhysicalMeasurementSynchronizationJSON=="" && ...
    missingSync.PhysicalMeasurementCFOStatus=="not_recorded", ...
    'Absent pre-plane sync evidence must not be filled from post-plane values.');
assert(~missingSync.PhysicalMeasurementDemodulationReceiptAvailable&& ...
    missingSync.PhysicalMeasurementDemodulationReceiptJSON==""&& ...
    missingSync.PhysicalMeasurementDemodulationReceiptSHA256=="", ...
    'Wholly absent original sync/receipt evidence must not acquire a reconstructed receipt.');
assert(trial.SINRMeasurementDomain=="selected_precoder_layer_receiver_objective" && ...
    trial.SINRMeasurementDomain~=trial.MeasuredTrialSINRMeasurementDomain);
csv=fullfile(runFolder,'independent_csirs_receiver.csv');
writetable(trial,csv);
persisted=readtable(csv,'TextType','string','VariableNamingRule','preserve', ...
    'Delimiter',',','ReadVariableNames',true,'NumHeaderLines',0);
for prefix=["Receiver","PhysicalMeasurement"]
    assert(persisted.(prefix+"TimingCorrection_samples")==trial.(prefix+"TimingCorrection_samples") && ...
        persisted.(prefix+"SynchronizationJSON")==trial.(prefix+"SynchronizationJSON") && ...
        persisted.(prefix+"CFOStatus")==trial.(prefix+"CFOStatus"), ...
        'Independent plane synchronization must survive production CSV export.');
end
for name=[noiseFields,"ConfiguredSNR_dB","MeasuredTrialSINR_dB","SINR_dB", ...
        "MeasurementRSRP_dB_re_UnitOccupiedRE_Es", ...
        "MeasurementRSSI_dB_re_UnitOccupiedRE_Es","MeasurementRSRQ_dB", ...
        "MeasurementRSRQNumeratorRSRP_dB_re_UnitOccupiedRE_Es", ...
        "MeasurementRSRQDenominatorRSSI_dB_re_UnitOccupiedRE_Es"]
    assert(abs(persisted.(name)-trial.(name))<=1e-12*max(1,abs(trial.(name))), ...
        'Actual receiver/calibration field %s must survive CSV export.',name);
end
assert(isnan(persisted.MeasurementRSRP_dBm) && isnan(persisted.MeasurementRSSI_dBm) && ...
    persisted.MeasurementPowerReferenceNormalized && ...
    persisted.MeasurementSource==trial.MeasurementSource && ...
    persisted.PhysicalMeasurementStatus==trial.PhysicalMeasurementStatus, ...
    'CSV serialization must preserve relative power units and receiver provenance, not invent dBm.');
assert(persisted.SINRMeasurementDomain==trial.SINRMeasurementDomain && ...
    persisted.MeasuredTrialSINRMeasurementDomain==trial.MeasuredTrialSINRMeasurementDomain);
assert(trial.ResultAvailableAtSample==trial.ObservationEndSampleExclusive && ...
    trial.ObservationStartSample==0 && trial.ObservationSampleRateHz==owner.SampleRateHz, ...
    "CSI publication must retain the actual shared receiver completion clock.");
assert(string(trial.RuntimeTransportMode)== ...
    "shared_physical_stream_independent_CSIRS_received_completion" && ...
    ~contains(lower(string(trial.MeasurementSource)),["proxy","fallback","synthetic"]), ...
    "Primary CSI evidence must remain actual shared-stream receiver evidence.");
assert(isempty(owner.Pending) && isempty(owner.DataTransmissions), ...
    "The focused measurement must not require or fabricate PDSCH/DCI/HARQ.");
assert(numel(owner.CSIRSTransmissions)==1 && ...
    owner.CSIRSTransmissions.Slot==1 && ...
    owner.CSIRSTransmissions.CommittedAtSample==owner.CSIRSTransmissions.EndSampleExclusive && ...
    owner.CSIRSTransmissions.EndSampleExclusive<=owner.Events.NextSampleIndex, ...
    "The physical owner must retain one completed cell-common CSI-RS TX record.");
referenceCalendar=table(1,'VariableNames',{'CSIReferenceSlot'});
[eligible,referenceEvidence]=sixgr.truth.resolveCSIReceiveReferenceEvidence( ...
    state,cfgUE,1,1,referenceCalendar,4);
assert(eligible && height(referenceEvidence)==1 && ...
    referenceEvidence.Slot==1 && isnan(referenceEvidence.EmbeddingUEIndex) && ...
    referenceEvidence.Source== ...
    "gnb_completed_independent_csirs_TX_not_UE_measurement_outcome", ...
    ["The independently scheduled gNB receiver must bind the completed " + ...
     "cell-common CSI-RS TX ledger, not the obsolete PDSCH-embedded ledger."]);
receiveCfg=cfgUE;
receiveCfg.phy.csi.reportPeriodicitySlots=5;
receiveCfg.phy.csi.reportOffsetSlots=4;
hypothesis=sixgr.truth.buildConfiguredPUCCHCSIReception( ...
    state,receiveCfg,1,5,"focused_independent_csirs_report_slot_5");
assert(hypothesis.SelectedTransport=="PUCCH" && ...
    height(hypothesis.CSIReferenceTransmissionEvidence)==1 && ...
    hypothesis.CSIReferenceTransmissionEvidence.Slot==1, ...
    "The production CSI-only gNB hypothesis must consume the physical CSI-RS TX ledger.");
assert(~isempty(state.ObservedREAllocationTable) && ...
    any(string(state.ObservedREAllocationTable.channel)=="CSI-RS"), ...
    "Actual independent CSI-RS RE ownership must be retained for exports.");
fprintf(["SHARED_INDEPENDENT_CSIRS_COMPLETION_PASS CQI=%g RI=%g PMI=%g " + ...
    "SINR=%g available_sample=%g\n"],trial.CQI,trial.RI,trial.PMI, ...
    trial.SINR_dB,trial.ResultAvailableAtSample);
ok=true;
end

function state=localReceive(state,items)
for item=reshape(items,1,[])
    assert(item.Kind=="CSIRS", ...
        "The focused source slot must complete only CSI-RS.");
    [~,~,~,executed]=sixgr.truth.sharedObservationEvidence( ...
        item.Planes,item.Context.Prepared);
    state.TestCSIRSExecutedNoiseEvidence=executed;
    p=item.Context.Prepared;
    [~,physical,~,~,actual]=sixgr.truth.sharedObservationEvidence(item.Planes,p);
    state.TestCSIRSReceiverSamples=actual.readComplete();
    state.TestCSIRSPhysicalMeasurementSamples=physical.readComplete();
    unscored=sixgr.phy.refsig.receiveCSIRSWaveform(p.Carrier,p.ReceiverConfig, ...
        actual.readComplete(),physical.readComplete(), ...
        [0 actual.EndSampleExclusive-actual.StartSample-p.NumSamples],executed);
    assert(isa(unscored.CSIMeasurementState,'sixgr.phy.mimo.CSIMeasurementState'), ...
        'test:CSIReceiverStateMissing','Receiver failed before independent scoring: %s; timing=%s', ...
        jsonencode(unscored.CSIRSChannelEstimation),jsonencode(unscored.ReceiveTiming));
    [unscoredCSI,~]=sixgr.phy.refsig.computeCSIRSFeedback(p.Carrier,p.ReceiverConfig,unscored);
    directRow=sixgr.truth.buildIndependentCSIRSTrialRow( ...
        p.ReceiverConfig,p,unscored,unscoredCSI,item.Context);
    assert(directRow.PhysicalMeasurementReferencePlane== ...
        "supplied_receive_columns_pre_RX_front_end" && ...
        ~directRow.PhysicalMeasurementPlaneBindingAvailable && ...
        ~directRow.PhysicalMeasurementStandardizedReferencePointQualified && ...
        ~directRow.PhysicalMeasurementHardwareQualified, ...
        'test:CSIDirectRowPlane','A direct receiver row has no physical owner binding.');
    before=state.SharedWaveformStream.Events.NextSampleIndex;
    [state,completedRow,reception,csi]=sixgr.truth.completeSharedCSIRSReception(state,item);
    % Only the power-plane metadata may acquire original owner authority;
    % all actual reports, estimates and the immutable CSI state stay exact.
    assert(csi.MeasurementPowerReferencePlane==reception.CSIRSObservation.PowerReferencePlane);
    assert(isequaln(rmfield(unscoredCSI,'MeasurementPowerReferencePlane'), ...
            rmfield(csi,'MeasurementPowerReferencePlane')) && ...
        isequaln(unscored.CSIRSChannelEstimate,reception.CSIRSChannelEstimate) && ...
        isequaln(unscored.CSIRSNoiseVar,reception.CSIRSNoiseVar) && ...
        isequaln(unscored.RxGrid,reception.RxGrid) && ...
        unscored.PhysicalMeasurementDemodulationReceiptJSON==reception.PhysicalMeasurementDemodulationReceiptJSON && ...
        unscored.PhysicalMeasurementDemodulationReceiptSHA256==reception.PhysicalMeasurementDemodulationReceiptSHA256 && ...
        unscored.CSIMeasurementState.Digest==reception.CSIMeasurementState.Digest && ...
        state.SharedWaveformStream.Events.NextSampleIndex==before, ...
        'test:CSIRSScoringChangedReceiver','Scoring must not change CSI/RI/PMI or execute the channel again.');
    assert(completedRow.PhysicalMeasurementPlaneBindingAvailable && ...
        completedRow.PhysicalMeasurementReferencePlane== ...
            "internal_physical_receive_element_before_RX_front_end" && ...
        completedRow.PhysicalMeasurementObservationHashPlane==completedRow.PhysicalMeasurementReferencePlane && ...
        ~completedRow.PhysicalMeasurementStandardizedReferencePointQualified && ...
        ~completedRow.PhysicalMeasurementHardwareQualified, ...
        'test:CSIOwnerPlaneBinding','Original element proof must survive actual multiport CSI completion.');
    plane=jsondecode(completedRow.PhysicalMeasurementPlaneBindingJSON);
    assert(plane.ReceiverWindowID==string(item.ID) && ...
        string(plane.OriginalInputSHA256)==physical.sampleHash() && ...
        plane.ReceiveElementBinding.Available && ...
        completedRow.PhysicalMeasurementPlaneBindingSHA256==sixgr.util.sha256Hex( ...
            char(completedRow.PhysicalMeasurementPlaneBindingJSON)));
    planeID='sixgr:truth:CSIPhysicalPlaneBinding';
    altered=unscored;
    altered.PhysicalMeasurementDemodulationReceiptSHA256="wrong_input_receipt_hash";
    localReject(@()sixgr.truth.bindSharedCSIRSMeasurementPlane( ...
        altered,item,executed,state.SharedWaveformStream),planeID);
    badReplay=executed; badReplay.ReceiverID="not_the_original_receiver";
    localReject(@()sixgr.truth.bindSharedCSIRSMeasurementPlane( ...
        unscored,item,badReplay,state.SharedWaveformStream),planeID);
    badReplay=executed;
    badReplay.ReceiveStreamExecutionSegments{1}.Execution.ConfigurationEpoch= ...
        badReplay.ReceiveStreamExecutionSegments{1}.Execution.ConfigurationEpoch+1;
    localReject(@()sixgr.truth.bindSharedCSIRSMeasurementPlane( ...
        unscored,item,badReplay,state.SharedWaveformStream),'RF:ReceiveElementObservation');
    replacement=sixgr.phy.waveform.WaveformObservationBuffer(physical.StartSample, ...
        physical.EndSampleExclusive,physical.SampleRateHz,physical.NumReceiveAntennas);
    replacement.append(sixgr.phy.waveform.WaveformChunk( ...
        .5*physical.readComplete(),physical.StartSample),physical.SampleRateHz);
    badItem=item;
    preIndex=find(string({item.Planes.ReceiverID})==string(executed.ReceiverID)+":pre_rf");
    badItem.Planes(preIndex).Observation=replacement;
    localReject(@()sixgr.truth.bindSharedCSIRSMeasurementPlane( ...
        unscored,badItem,executed,state.SharedWaveformStream),planeID);
    fprintf('CSI_OWNER_PLANE_BINDING_PASS original_multiport_capture=1 negatives=4 numeric_CSI_unchanged=1\n');
    audit=load(fullfile(p.ReceiverConfig.run.rootRunFolder,completedRow.CSISelectionQualityMATFile));
    badRow=completedRow; badRow.ReceiverWindowID="different_completed_window";
    localReject(@()sixgr.truth.bindSharedCSISelectionQuality( ...
        p.ReceiverConfig.run.rootRunFolder,badRow,p,reception,csi,item.Planes,audit.Inputs.Reference,item.ID), ...
        'sixgr:truth:CSISelectionBindingWindowIdentity');
    badRow=removevars(completedRow,'ReceiverWindowID');
    localReject(@()sixgr.truth.bindSharedCSISelectionQuality( ...
        p.ReceiverConfig.run.rootRunFolder,badRow,p,reception,csi,item.Planes,audit.Inputs.Reference,item.ID), ...
        'sixgr:truth:CSISelectionBindingWindowIdentity');
    bad=reception;
    bad.ReceiverSynchronizationEvidence.InputSHA256="different_capture";
    localReject(@()sixgr.truth.bindSharedCSISelectionQuality( ...
        p.ReceiverConfig.run.rootRunFolder,completedRow,p,bad,csi,item.Planes,audit.Inputs.Reference,item.ID), ...
        'sixgr:truth:CSISelectionBindingFFTInput');
    badReference=audit.Inputs.Reference;
    badReference.FFTEndSampleExclusive(:)=completedRow.ObservationEndSampleExclusive+1;
    localReject(@()sixgr.truth.bindSharedCSISelectionQuality( ...
        p.ReceiverConfig.run.rootRunFolder,completedRow,p,reception,csi,item.Planes,badReference,item.ID), ...
        'sixgr:truth:CSISelectionBindingFFTSupport');
    state.TestCSIRSReception=reception;
    state.TestCSIRSReport=csi;
    state.TestCSIRSContext=item.Context;
    p=item.Context.Prepared;
    observed=sixgr.truth.buildObservedREAllocation(p.Tx, ...
        "Direction","DL","Channel","CSI-RS", ...
        "AbsoluteSlot",item.Context.Slot-1,"CellID",item.Context.ServingCell, ...
        "UEID",NaN,"AllocationID","csirs_cell_1_slot_0");
    state.ObservedREAllocationTable=localAppend( ...
        sixgr.util.structGet(state,"ObservedREAllocationTable",table()),observed);
end
end

function localReject(fn,id)
try
    fn();
catch err
    assert(strcmp(err.identifier,id),'test:WrongCSISelectionRejection', ...
        'Expected %s, received %s: %s',id,err.identifier,err.message);
    return;
end
error('test:MissingCSISelectionRejection','Expected %s.',id);
end

function out=localAppend(out,rows)
if isempty(out)
    out=rows;
    return;
end
if isempty(rows)
    return;
end
missing=setdiff(out.Properties.VariableNames,rows.Properties.VariableNames,"stable");
for name=string(missing)
    rows.(name)=out.(name)(1+zeros(height(rows),1),:);
end
missing=setdiff(rows.Properties.VariableNames,out.Properties.VariableNames,"stable");
for name=string(missing)
    out.(name)=rows.(name)(1+zeros(height(out),1),:);
end
rows=rows(:,out.Properties.VariableNames);
out=[out;rows];
end
