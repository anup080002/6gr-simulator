function testMalformedAuditNeverThrows(testCase)
subcases=table("SC-00",true,"PASS", ...
    'VariableNames',{'SubcaseID','Executed','Status'});
values=table("V",true,"PASS", ...
    'VariableNames',{'CheckID','Required','Status'});
components=table("C","PASS", ...
    'VariableNames',{'ComponentID','Status'});
malformed=struct("UnexpectedField","not-an-artifact-table");
publication=table("PASS",'VariableNames',{'Status'});
regression=table("R","PASS",0,0, ...
    'VariableNames',{'Suite','Status','SkippedTests','BlockedTests'});
acceptance=table("A",true,"PASS", ...
    'VariableNames',{'RuleID','Required','Status'});
result=sixgr.integration.qualification. ...
    QualificationFinalizationCoordinator.assess( ...
    subcases,values,components,malformed,publication, ...
    regression,acceptance);
verifyFalse(testCase,result.FinalManifestComplete);
verifyEqual(testCase,result.ArtifactSchemaDiagnostic.Status,"FAIL");
end
