function ok=testSRSFixedMatrixChannelPreservation()
% Actual standalone SRS waveform reception, not shared-network qualification.
% The fixed channel is a generation/scoring input, never receiver Hest.
setup6GRSimToolkit('Verbose',false,'RunToolboxChecks',false);
scenario=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_tdd_5mhz_rank2_4tx2rx_awgn_m10db.yaml');
folder=fullfile(pwd,'results','lls','srs_fixed_matrix_channel', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(folder);
cfg=sixgr.lls6g.buildInternalConfig(scenario,folder);
matrix=cfg.channel.awgnSpatialMatrixDL;
assert(isequal(size(matrix),[2 4]));
% Use the practical general estimator: this checks propagation, not the
% independently qualified opt-in static-AWGN estimator.
cfg.phy.srs.runtimeChannelEstimator='nr_channel_estimate';
strict=sixgr.phy.srs.buildSRSConfigFromScenario(cfg);
slot=double(strict.ExpectedSlotSet(1))+1;
previous=rng; restore=onCleanup(@()rng(previous));
rows=struct([]);
for amplitude=[1 .5]
    cfg.channel.awgnSpatialMatrixDL=amplitude*matrix;
    rng(6100401,'twister');
    out=sixgr.link.runSRSChannelEstimation(cfg,'SNR_dB',40,'SlotIndex',slot);
    power=double(out.SRSRSRPPerReceiveAntenna_dB_re_UnitOccupiedRE_Es);
    row=struct('ChannelAmplitude',amplitude,'ConfiguredTxPorts',2, ...
        'ConfiguredReceiveBranches',4,'MeasuredReceiveBranches',numel(power), ...
        'MeasuredReferencePower_dB',out.SRS_RSRP_dB_re_UnitOccupiedRE_Es, ...
        'TrialOK',out.Ok,'RuntimeEvidenceUsable',out.SRSRuntimeEvidenceUsable, ...
        'ChannelEstimateAvailable',out.ChannelEstimateAvailable, ...
        'RuntimeChannelStateUsed',out.RuntimeChannelStateUsed, ...
        'ChannelFadingApplied',out.ChannelFadingApplied, ...
        'FailureReason',string(out.FailureReason),'Notes',string(out.Notes), ...
        'Scope',"physical_standalone_SRS_not_shared_runtime_qualification");
    rows=[rows;row]; %#ok<AGROW>
    save(fullfile(folder,sprintf('amplitude_%g.mat',amplitude)),'cfg','out');
end
T=struct2table(rows); writetable(T,fullfile(folder,'channel_preservation.csv'));
disp(T); fprintf('SRS_FIXED_MATRIX_EVIDENCE=%s\n',folder);
assert(all(T.ChannelEstimateAvailable & T.RuntimeChannelStateUsed), ...
    'test:SRSFixedMatrixReception','SRS must reach the physical channel and practical receiver.');
assert(all(T.TrialOK & T.RuntimeEvidenceUsable), ...
    'test:SRSFixedMatrixReceiver','Retain failures after channel estimation instead of accepting partial receiver output.');
assert(~any(T.ChannelFadingApplied), ...
    'test:SRSFixedMatrixClassification','A fixed spatial matrix is not small-scale fading.');
assert(all(T.MeasuredReceiveBranches==T.ConfiguredReceiveBranches), ...
    'test:SRSFixedMatrixBranches', ...
    'SRS discarded the 2-TX/4-RX channel output before receiver measurement.');
measuredChange=T.MeasuredReferencePower_dB(2)-T.MeasuredReferencePower_dB(1);
assert(isfinite(measuredChange) && abs(measuredChange-20*log10(.5))<.15, ...
    'test:SRSFixedMatrixGain','Halving physical channel amplitude must lower measured SRS power by 6.02 dB.');
ok=true;
end
