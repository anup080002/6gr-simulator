function ok = testHARQIRCombiningGain()
%TESTHARQIRCOMBININGGAIN Guard HARQ combining-gain source selection.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

layout = sixgr.report.resultLayout(tmp);
sixgr.util.ensureFolder(layout.HARQCSVDir);
sixgr.util.ensureFolder(layout.AirInterfaceCSVDir);

live = table( ...
    "DL", 0, false, false, true, true, NaN, 100, 100, NaN, ...
    'VariableNames', {'Direction','RV','IsRetransmission','HARQCombiningApplied', ...
    'CurrentDecodeOK','CombinedDecodeOK','PreviousLLRCount','CurrentLLRCount', ...
    'CombinedLLRCount','LLRCombiningGain_dB'});
sixgr.util.csvWriteTable(fullfile(layout.HARQCSVDir, "live_harq_observation_timeline.csv"), live);

probe = table( ...
    ["DL"; "DL"], [0; 2], [false; true], [false; true], ...
    [false; false], [false; true], [NaN; 100], [100; 100], [100; 200], ...
    [NaN; 3.0103], ["closed_loop"; "closed_loop"], ...
    'VariableNames', {'Direction','RV','IsRetransmission','HARQCombiningApplied', ...
    'CurrentDecodeOK','CombinedDecodeOK','PreviousLLRCount','CurrentLLRCount', ...
    'CombinedLLRCount','LLRCombiningGain_dB','ProbeMode'});
sixgr.util.csvWriteTable(fullfile(layout.HARQCSVDir, "probe_harq_packets.csv"), probe);

gain = sixgr.analytics.measureHARQCombiningGain(table(), tmp);

assert(height(gain) == 1, "HARQ combining-gain analysis must emit one summary row.");
assert(string(gain.SourceArtifact) == "harq/csv/probe_harq_packets.csv", ...
    "Combining-gain analysis must prefer probe HARQ evidence over a no-retx live timeline.");
assert(logical(gain.Exercised), ...
    "Probe HARQ combining evidence must mark the analysis exercised.");
assert(double(gain.RetransmissionAttempts) == 1 && double(gain.CombiningAppliedCount) == 1, ...
    "Probe HARQ combining evidence must preserve retransmission and combining counts.");
assert(double(gain.CombinedRecoveryCount) == 1, ...
    "Probe HARQ combining evidence must preserve recovery-after-combining counts.");
assert(abs(double(gain.MeanLLRCombiningGain_dB) - 3.0103) < 1e-9, ...
    "Probe HARQ combining evidence must drive the reported mean LLR combining gain.");

ok = true;
end
