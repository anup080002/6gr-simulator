function ok = testLLSLiveStageTraceRuntimeMerge()
%TESTLLSLIVESTAGETRACERUNTIMEMERGE Verify live stage trace preserves both DL and UL rows.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
cfg.run.numFrames = 2;
cfg.channel.snr_dB = 10;

opt = struct( ...
    "LinkDuration_s", max(double(cfg.run.numFrames) * 1e-3, 2e-3), ...
    "LinkMaxSimFrames", double(cfg.run.numFrames), ...
    "LinkSNR_dB", 10, ...
    "LinkSNRGrid_dB", 10, ...
    "LinkSweepFrames", 1, ...
    "LinkSweepTrialsPerSNR", 1, ...
    "LinkReferenceSweepFrames", 1, ...
    "LinkSweepMaxPoints", 1, ...
    "LinkAdaptiveSweepEnabled", false, ...
    "LinkAdaptiveSweepStep_dB", 2, ...
    "LinkAdaptiveSweepMaxPoints", 1, ...
    "SaveFigures", false);

runFolder = fullfile(tmp, "air_interface");
sixgr.truth.runWaveformLinkBundle(cfg, runFolder, opt);

stagePath = fullfile(tmp, "reports", "csv", "live_tx_rx_stage_trace.csv");
assert(exist(stagePath, "file") == 2, ...
    "Live stage trace export must exist after waveform bundle execution.");
stageT = readtable(stagePath, "VariableNamingRule", "preserve");
assert(istable(stageT) && ~isempty(stageT), ...
    "Live stage trace export must be non-empty.");
assert(any(strcmpi(string(stageT.Direction), "DL")) && any(strcmpi(string(stageT.Direction), "UL")), ...
    "Live stage trace export must preserve both DL and UL runtime rows.");

ok = true;
end
