function ok = testSchedulerHARQContextIsolation()
%TESTSCHEDULERHARQCONTEXTISOLATION Keep nested HARQ authority per UE/grant.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
localAssertFirstTransmissionSizeBinding();
localAssertMixedGrantIsolation("PF");
localAssertMixedGrantIsolation("RR");
ok = true;
end

function localAssertFirstTransmissionSizeBinding()
cfg = sixgr.config.defaultConfig();
harq = sixgr.l2.mac.HARQEntity(cfg, "Direction", "UL", ...
    "NumProcesses", 2, "MaxRetx", 3, "StoreTB", true);
rnti = 4001;
tentativeBytes = 1857;
actualBits = 7304;
txp = harq.allocate(rnti, 0, tentativeBytes, "NewData", true);
grant = struct("Direction", "UL", "RNTI", rnti, ...
    "TBSBits", actualBits, "TBSBytes", actualBits / 8, ...
    "HARQ", txp.HARQ, "IsRetransmission", false, ...
    "HARQTBContext", struct("TBId", "actual_first_tx", ...
    "TBSBits", actualBits, "HARQProcessId", txp.HARQ.HarqID, ...
    "NDI", txp.HARQ.NDI, "NDIEpoch", txp.HARQ.NDIEpoch));
payload = zeros(actualBits, 1, "uint8");
harq.onTx(rnti, txp.HARQ.HarqID, payload, grant, 0);
harq.onFeedback(rnti, txp.HARQ.HarqID, "NACK", ...
    "SourceSlot", 0, "FeedbackSlot", 4);
replay = harq.peekRetx(rnti, 5);
assert(double(replay.TBSBytes) * 8 == actualBits && ...
    numel(replay.TB) == actualBits && ...
    double(replay.TBContext.TBSBits) == actualBits, ...
    ['The executed first transmission, not a tentative pre-PHY ' ...
    'scheduler reservation, must bind the immutable replay size.']);
end

function localAssertMixedGrantIsolation(kind)
cfg = sixgr.config.defaultConfig();
cfg.mac.scheduler.maxUEPerSlot = 2;
cfg.mac.scheduler.maxUEPerSlotDL = 2;
cfg.mac.scheduler.minPRBPerUE = 4;
cfg.mac.scheduler.maxPRBAllocationPerUE = 12;
cfg.mac.scheduler.muMimoEnabled = false;
cfg.mac.harq.enable = true;
cfg.mac.harq.numProcesses = 4;
cfg.mac.harq.maxRetx = 3;
cfg = withCanonicalSchedulerTiming(cfg);

harq = sixgr.l2.mac.HARQEntity(cfg, "Direction", "DL", ...
    "NumProcesses", 4, "MaxRetx", 3, "StoreTB", true);
if upper(string(kind)) == "PF"
    scheduler = sixgr.l2.mac.SchedulerPF(cfg, "Direction", "DL", "HARQ", harq);
else
    scheduler = sixgr.l2.mac.SchedulerRR(cfg, "Direction", "DL", "HARQ", harq);
end

ues = repmat(struct("RNTI", 0, "UEIndex", 0, "ServingCell", 1, ...
    "DLBufferBytes", 0, "ULBufferBytes", 0, "CQI", 8, "RI", 1, ...
    "HeadOfLineDelay_ms", 1, "ControlEligible", true, ...
    "GrantControlState", "ok"), 1, 2);
ues(1).RNTI = 4101;
ues(1).UEIndex = 1;
ues(1).DLBufferBytes = 20000;
ues(2).RNTI = 4102;
ues(2).UEIndex = 2;
ues(2).CQI = 15;

budget = struct("PRBSet", 0:47, "ControlSymbolAllocation", [0 2], ...
    "SymbolAllocation", [2 12]);
first = scheduler.schedule(0, ues, budget);
assert(numel(first) == 1 && double(first.RNTI) == 4101, ...
    "%s fixture must first allocate only UE 4101.", kind);
first = first(1);
harqId = double(first.HARQ.HarqID);
receiveCombiner = complex(zeros(64, 2));
receiveCombiner(1, 1) = 1;
receiveCombiner(2, 2) = 1;
first.MUMIMOReceiveCombiningMatrix = receiveCombiner;
first.MUMIMOReceiveCombiningMatrixSHA256 = char( ...
    sixgr.phy.mimo.MatrixContract.digest(receiveCombiner));
first.NumRFChains = 32;
first.NumLogicalPorts = 4;
first.HARQTBContext = struct( ...
    "TBId", "ue4101_original_tb", ...
    "OriginalNumLayers", double(first.NumLayers), ...
    "TBSBits", double(first.TBSBits), ...
    "HARQProcessId", harqId, ...
    "NDI", logical(first.HARQ.NDI), ...
    "NDIEpoch", double(sixgr.util.structGet(first.HARQ, "NDIEpoch", 1)));
payload = zeros(round(double(first.TBSBits)), 1, "uint8");
harq.onTx(4101, harqId, payload, first, 0);
harq.onFeedback(4101, harqId, "NACK", ...
    "SourceSlot", 0, "FeedbackSlot", 4);

ues(2).DLBufferBytes = 913;
mixed = scheduler.schedule(5, ues, budget);
assert(numel(mixed) == 2, ...
    "%s fixture must return one retransmission and one new-data grant.", kind);
replay = mixed([mixed.RNTI] == 4101);
newData = mixed([mixed.RNTI] == 4102);
assert(numel(replay) == 1 && numel(newData) == 1, ...
    "%s fixture must retain one grant per UE.", kind);
assert(logical(sixgr.phy.grant.isExplicitHARQRetransmission( ...
    replay, sixgr.util.structGet(replay, "PHYGrant", struct()), struct())), ...
    "%s retransmission grant must retain explicit replay authority.", kind);
assert(isstruct(replay.HARQTBContext) && ...
    string(replay.HARQTBContext.TBId) == "ue4101_original_tb" && ...
    double(replay.HARQTBContext.TBSBits) == double(first.TBSBits), ...
    "%s retransmission must retain its own immutable TB context.", kind);
assert(~logical(sixgr.phy.grant.isExplicitHARQRetransmission( ...
    newData, sixgr.util.structGet(newData, "PHYGrant", struct()), struct())), ...
    "%s new-data grant must not inherit retransmission authority.", kind);
assert(~isfield(newData, "HARQTBContext") || ...
    ~(isstruct(newData.HARQTBContext) && ...
    ~isempty(fieldnames(newData.HARQTBContext))), ...
    "%s new-data grant inherited another UE's HARQ TB context.", kind);
assert(double(newData.TBSBits) ~= double(replay.HARQTBContext.TBSBits), ...
    "%s fixture must exercise distinct new-data and replay TB sizes.", kind);
assert(isequal(replay.MUMIMOReceiveCombiningMatrix, receiveCombiner) && ...
    string(replay.MUMIMOReceiveCombiningMatrixSHA256) == ...
        string(first.MUMIMOReceiveCombiningMatrixSHA256), ...
    "%s retransmission must retain its own measured receive combiner.", kind);
assert(isempty(newData.MUMIMOReceiveCombiningMatrix) && ...
    strlength(string(newData.MUMIMOReceiveCombiningMatrixSHA256)) == 0, ...
    ["%s new-data grant inherited a manufactured zero receive combiner " ...
     "from another UE's retransmission."], kind);
assert(isnan(double(newData.NumRFChains)) && ...
    isnan(double(newData.NumLogicalPorts)), ...
    "%s schema alignment manufactured zero RF-chain/port authority.", kind);
end
