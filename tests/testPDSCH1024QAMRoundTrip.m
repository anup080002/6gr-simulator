function ok = testPDSCH1024QAMRoundTrip()
%TESTPDSCH1024QAMROUNDTRIP Exercise every production 1024-QAM point.

setup6GRSimToolkit("Verbose", false);
labels = dec2bin(0:1023, 10).' - '0';
bits = int8(labels(:));
[symbols, mapInfo] = sixgr.pdsch.PDSCHModulator(bits, "1024QAM");
hardBits = sixgr.pdsch.PDSCHModulator( ...
    symbols, "1024QAM", "Operation", "hard-demap");
softLLR = sixgr.pdsch.PDSCHModulator( ...
    symbols, "1024QAM", "Operation", "soft-demap", ...
    "NoiseVariance", 1e-3, "Algorithm", "max-log");

assert(mapInfo.Qm == 10 ...
    && mapInfo.NormalizationDenominatorSquared == 682);
assert(numel(unique(symbols)) == 1024, ...
    "The production 1024-QAM mapper did not emit 1024 unique points.");
assert(abs(mean(abs(symbols).^2) - 1) < 5e-14, ...
    "The complete production 1024-QAM constellation is not unit power.");
assert(isequal(hardBits(:), bits) ...
    && isequal(int8(softLLR < 0), bits), ...
    "Production 1024-QAM map/demap is not bit exact.");
fprintf("PDSCH 1024-QAM round trip: 1024/1024 points and 10240/10240 bits pass\n");
ok = true;
end
