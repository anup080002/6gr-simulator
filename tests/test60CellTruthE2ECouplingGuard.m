function ok = test60CellTruthE2ECouplingGuard()
%TEST60CELLTRUTHE2ECOUPLINGGUARD Combined truth E2E runs must be system-coupled.

setup6GRSimToolkit("Verbose", false);

cfg = sixgr.config.defaultConfig();
cfg.scenario.layout.nSites = 20;
cfg.scenario.layout.nSectorsPerSite = 3;
cfg.scenario.ue.nUE = 100;
cfg.scenario.nUE = 100;

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tempname, ...
    "RunLinkCampaign", false, ...
    "RunDetailedLinkDiagnostics", false, ...
    "RunSystemMMTCProbe", false, ...
    "RunAuxiliaryProbes", false, ...
    "RunE2EStackProbe", true, ...
    "OnlyE2E", false, ...
    "E2EAirModel", "truth", ...
    "E2EDuration_s", 0.01, ...
    "E2EMaxSlots", 20, ...
    "E2EUECount", 100, ...
    "SystemDuration_s", 0.01, ...
    "SystemNumUE", 100, ...
    "CalibrateSystemBLERFromLink", false, ...
    "UseFastLinkModel", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "GenerateCampaignPlots", false, ...
    "VerifyArtifacts", false, ...
    "Verbose", false);

assert(rep.Ok, "Combined system + truth E2E campaign should complete cleanly once coupling exists.");
assert(isfield(rep, "E2E") && logical(sixgr.util.structGet(rep.E2E, "SystemCoupled", false)), ...
    "Combined truth E2E run must report system coupling.");
assert(string(sixgr.util.structGet(rep.E2E, "CouplingMode", "")) == "system_waveform_grant_trace", ...
    "Combined truth E2E run must use the waveform system grant trace coupling mode.");
ok = true;
end
