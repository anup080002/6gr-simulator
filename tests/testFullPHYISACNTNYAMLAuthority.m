function ok = testFullPHYISACNTNYAMLAuthority()
%TESTFULLPHYISACNTNYAMLAUTHORITY Guard both isolated master surfaces.

setup6GRSimToolkit("Verbose",false,"RunToolboxChecks",false);
root = fullfile(pwd,"simulator","configs","scenarios");
tmp = string(tempname);
mkdir(tmp);
cleanup = onCleanup(@() localCleanup(tmp)); %#ok<NASGU>

sinr = localLoadBuild(root,"master_sinr_sweep.yaml",tmp);
geometry = localLoadBuild(root,"master_geometry_based.yaml",tmp);
localAssertCompleteDisabledSurface(sinr.Raw,sinr.Cfg);
localAssertCompleteDisabledSurface(geometry.Raw,geometry.Cfg);

scenarioPath = fullfile(root, ...
    "webgui_sinr_plus20_2x2_mu_mimo_isac_full_phy.yaml");
scenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
sourceFiles = lower(replace(string(scenario.SourceFiles),"\","/"));
assert(any(endsWith(sourceFiles,"/master_sinr_sweep.yaml")) && ...
    ~any(endsWith(sourceFiles,"/master_geometry_based.yaml")));
cfg = sixgr.lls6g.buildInternalConfig(scenario,fullfile(tmp,"isac_enabled"));
assert(cfg.isac.enabled && cfg.lls6g.isac.enabled);
assert(~cfg.ntn.enabled && ~cfg.lls6g.ntn.enabled);
assert(string(cfg.isac.waveformAuthority) == "exact_runtime_pdsch_waveform");
assert(string(cfg.isac.executionScope) == "first_committed_dl_grant");
assert(string(cfg.isac.output.imageFormat) == "png" && ...
    logical(cfg.isac.output.prohibitSVG));

bad = cfg;
bad.isac.output.savePNG = false;
localAssertError(@() sixgr.isac.validateConfig(bad), ...
    "sixgr:isac:IncompleteOutputContract");
bad = cfg;
bad.ntn.enabled = true;
localAssertError(@() sixgr.ntn.validateConfig(bad), ...
    "sixgr:ntn:ChannelProfileMismatch");
ok = true;
end

function out = localLoadBuild(root,name,tmp)
path = fullfile(root,name);
raw = sixgr.lls6g.config.readConfigFile(path);
scfg = sixgr.lls6g.config.loadScenarioConfig(path);
cfg = sixgr.lls6g.buildInternalConfig(scfg,fullfile(tmp,erase(name,".yaml")));
out = struct("Raw",raw,"Cfg",cfg);
end

