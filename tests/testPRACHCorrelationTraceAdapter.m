function ok = testPRACHCorrelationTraceAdapter()
%TESTPRACHCORRELATIONTRACEADAPTER Guard alias handling and truth separation.

setup6GRSimToolkit("Verbose", false);
localRuntimeOutcomeAuthority();

sourceT = table((1:8).', (-3:4).', [0.1;0.2;0.4;0.9;0.5;0.3;0.2;0.1], ...
    repmat("real_lls_evidence", 8, 1), ...
    'VariableNames', ["SampleIndex","LagSamples","CorrelationAbs","TruthStatus"]);
T = sixgr.visual.normalizePRACHCorrelationTrace(sourceT);
required = ["trial_id","preamble_index","root_sequence_index","restricted_set_type","n_cs", ...
    "zero_correlation_zone_config","lag_samples","lag_us","correlation_abs","threshold", ...
    "noise_floor","peak_lag_samples","timing_advance_samples","detection_result", ...
    "false_alarm","missed_detection","snr_db","cfo_hz","seed","truth_status"];
assert(all(ismember(required, string(T.Properties.VariableNames))) && height(T) == 8, ...
    "PRACH trace adapter must emit the complete canonical schema.");
assert(isequal(T.lag_samples, (-3:4).') && isequal(T.correlation_abs, sourceT.CorrelationAbs), ...
    "PRACH trace adapter must preserve measured lag and correlation values exactly.");
assert(all(T.truth_status == "real_lls_evidence"), ...
    "Explicit source truth status must be preserved.");
assert(all(isnan(T.trial_id)) && all(isnan(T.false_alarm)), ...
    "Unavailable metadata must remain unavailable; the adapter must not invent identity or outcomes.");

noTruth = removevars(sourceT, "TruthStatus");
noTruthT = sixgr.visual.normalizePRACHCorrelationTrace(noTruth);
assert(all(noTruthT.truth_status == "not_available_missing_truth_status"), ...
    "A measured-looking trace without explicit truth provenance must not be promoted to real LLS evidence.");

ok = true;
fprintf("testPRACHCorrelationTraceAdapter: PASS\n");
end

function localRuntimeOutcomeAuthority()
% Receiver-export fixtures only; not noise-only statistical qualification.
trace=struct('LagSamples',31,'CorrelationAbs',.4,'Threshold',.02, ...
    'PeakLagSamples',31,'TraceStatus',"toolbox_peak_only_evidence", ...
    'DetectorBackend',"nrPRACHDetect", ...
    'LagReference',"offset_from_gnb_prach_slot_origin_within_actual_capture", ...
    'DetectorInputStartOffsetSamples',1229,'RawTimingOffsetSamples',1260, ...
    'PropagationTimingOffsetSamples',24,'ImplementationFilterDelay_samples',7);
ra=struct('Msg1DetectionTrace',trace,'Msg1Tx',struct('SampleRate_Hz',122.88e6), ...
    'PreambleDetected',true,'PreambleIndexDetected',5);
row=struct('FalseAlarm',NaN,'MissedDetection',false, ...
    'FalseAlarmClassification',"unavailable_complete_transmitted_occasion_set_not_retained", ...
    'PreambleIndex',5,'SweepPointIndex',3,'ConfiguredSNR_dB',20,'UEIndex',2,'CellID',1,'Slot',9);
cfg=struct('run',struct('seed',17));
for value=[NaN 0 1]
    row.FalseAlarm=value;
    out=sixgr.truth.buildFourStepRACorrelationTraceTable(ra,row,cfg,20,2);
    assert(isequaln(out.false_alarm,value),'test:PRACHFalseAlarmDefaulted', ...
        'Trace false alarm must preserve the actual per-trial tri-state evidence.');
    out=sixgr.truth.buildPRACHCorrelationTraceTable(out);
    assert(height(out)==1 && isequaln(out.false_alarm,value) && out.lag_samples==31 && ...
        out.trace_scope==trace.TraceStatus && out.detector_backend==trace.DetectorBackend && ...
        out.lag_reference==trace.LagReference && out.detector_input_start_offset_samples==1229 && ...
        out.raw_timing_offset_samples==1260 && out.propagation_timing_offset_samples==24 && ...
        out.sample_rate_hz==122.88e6 && out.sweep_point_index==3 && out.ue_index==2 && ...
        out.source_slot_1based==9 && out.target_preamble_index==5 && isnan(out.cfo_hz));
    assert(isequaln(sixgr.visual.normalizePRACHCorrelationTrace(out),out));
end
row=rmfield(row,'FalseAlarm');
out=sixgr.truth.buildFourStepRACorrelationTraceTable(ra,row,cfg,20,2);
assert(isnan(out.false_alarm),'Absent false-alarm evidence must not become zero.');
row.PreambleIndex=3; row.MissedDetection=true;
out=sixgr.truth.buildFourStepRACorrelationTraceTable(ra,row,cfg,20,2);
assert(out.missed_detection==1 && out.detection_result=="missed_detection" && ...
    out.preamble_index==5 && out.target_preamble_index==3, ...
    'Receiving a different target cannot clear the requested preamble''s miss.');
bad=ra; bad.Msg1DetectionTrace.CorrelationAbs=[.4 .5];
try
    sixgr.truth.buildFourStepRACorrelationTraceTable(bad,row,cfg,20,2);
    error('test:ExpectedPRACHTraceShapeFailure','Unpaired samples were silently truncated.');
catch cause
    assert(strcmp(cause.identifier,'sixgr:truth:PRACHTraceSampleMismatch'));
end
end
