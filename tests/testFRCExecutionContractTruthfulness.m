function ok = testFRCExecutionContractTruthfulness()
%TESTFRCEXECUTIONCONTRACTTRUTHFULNESS Fail closed on unimplemented FRC data.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

catalog = sixgr.conformance.frcCatalog();
entryIndex = localEntryIndex(catalog.entries, ...
    "dl_r_pdsch_1_1_4_fdd_awgn");
entry = localItem(catalog.entries, entryIndex);
entry.allocation.full_bandwidth = false;
entry.allocation.frequency_hopping = "enabled";
entry.allocation.resource_allocation_type = "Type1";
entry.allocation.rbg_size_config = "Config1";
entry.allocation.vrb_to_prb_mapping = "interleaved";
entry.allocation.allocated_slots_per_20ms = 18;
entry.waveform.transform_precoding = true;
entry.mimo.correlation_matrix = "custom_not_materialized";
entry.ptrs = struct( ...
    "enabled", true, ...
    "frequency_density", "2", ...
    "time_density", "1", ...
    "requirement_variant", "Yes");
catalog.entries = localReplaceItem(catalog.entries, entryIndex, entry);
catalogPath = localWriteTemporaryCatalog(catalog);
catalogCleanup = onCleanup(@() localDeleteIfPresent(catalogPath)); %#ok<NASGU>

cause = localExpectedExecutionBlock( ...
    entry.id, entry.condition.id, catalogPath);
expectedBlockers = [ ...
    "partial_bandwidth_allocation_not_materialized"; ...
    "frequency_hopping_not_materialized"; ...
    "transform_precoding_not_materialized"; ...
    "ptrs_not_materialized"; ...
    "unsupported_pdsch_resource_allocation_type"; ...
    "unsupported_pdsch_rbg_size_configuration"; ...
    "pdsch_vrb_to_prb_mapping_not_materialized"; ...
    "unsupported_pdsch_slots_per_20ms"; ...
    "unsupported_awgn_static_channel_contract"];
for blocker = expectedBlockers.'
    assert(contains(string(cause.message), blocker), ...
        "Missing fail-closed data-channel blocker '%s'.", blocker);
end

fadingResult = sixgr.conformance.runFRCPoint( ...
    "dl_r_pdsch_1_3_1_fdd_tdla30_10", ...
    "tdla30_10_ula_low_2x2", ...
    "ValidateSetupOnly", true, ...
    "RequireExactStandardExecution", false, ...
    "RequireExactDataChannelExecution", true, ...
    "PrintTable", false, "Verbose", false);
assert(logical(fadingResult.DataChannelExecution.Exact) && ...
    isempty(fadingResult.DataChannelExecution.Blockers), ...
    "The rank-2 fading FRC must materialize its explicit FDD HARQ " + ...
    "timeline and recognized ULA Low correlation contract.");

widebandCause = localExpectedExecutionBlock( ...
    "dl_r_pdsch_1_2_3_fdd_tdla30_10", ...
    "tdla30_10_ula_low_4x4_rank3", "");
assert(contains(string(widebandCause.message), ...
    "unsupported_pdsch_prb_bundling_size"), ...
    ("Rank-3 wideband PDSCH execution must fail closed until wideband " + ...
    "precoding is materialized."));

codebookCause = localExpectedExecutionBlock( ...
    "ul_g_fr1_a11_1_tdla30_10_rank4", ...
    "tdla30_10_low_4x4", "");
assert(contains(string(codebookCause.message), ...
    "pusch_codebook_precoding_not_materialized") && ...
    contains(string(codebookCause.message), ...
    "pusch_tpmi_not_materialized"), ...
    ("G-FR1-A11-1 must fail closed until codebook precoding and its " + ...
    "explicit TPMI index are materialized."));

localAssertToolboxCorrelationMatrices();
ok = true;
end

function cause = localExpectedExecutionBlock(entryId, conditionId, catalogPath)
args = { ...
    "ValidateSetupOnly", true, ...
    "RequireExactStandardExecution", false, ...
    "RequireExactDataChannelExecution", true, ...
    "PrintTable", false, ...
    "Verbose", false};
if strlength(string(catalogPath)) > 0
    args = [args, {"CatalogPath", catalogPath}]; %#ok<AGROW>
end
try
    sixgr.conformance.runFRCPoint(entryId, conditionId, args{:});
catch caught
    cause = caught;
    assert(string(cause.identifier) == ...
        "sixgr:conformance:IncompleteDataChannelExecution", ...
        "Unexpected fail-closed identifier '%s': %s", ...
        cause.identifier, getReport(cause, "extended", "hyperlinks", "off"));
    return;
end
error("sixgr:tests:FRCExecutionDidNotFailClosed", ...
    "FRC execution unexpectedly proceeded despite an incomplete contract.");
end

function localAssertToolboxCorrelationMatrices()
channel = nrTDLChannel;
cleanup = onCleanup(@() release(channel)); %#ok<NASGU>
channel.NumTransmitAntennas = 2;
channel.NumReceiveAntennas = 2;
channel.TransmissionDirection = "Downlink";
channel.MIMOCorrelation = "Medium";
channelInfo = info(channel);
actualMedium = double(channelInfo.SpatialCorrelationMatrix);
expectedMedium = [ ...
    1, 0.9, 0.3, 0.27; ...
    0.9, 1, 0.27, 0.3; ...
    0.3, 0.27, 1, 0.9; ...
    0.27, 0.3, 0.9, 1];
assert(max(abs(actualMedium - expectedMedium), [], "all") <= 5e-12, ...
    "nrTDLChannel Medium does not match the selected TS 38.101-4 matrix.");

channel.MIMOCorrelation = "Low";
channelInfo = info(channel);
actualLow = double(channelInfo.SpatialCorrelationMatrix);
assert(isequal(actualLow, eye(4)), ...
    "nrTDLChannel Low must be the exact uncorrelated 2x2 matrix.");
end

function path = localWriteTemporaryCatalog(catalog)
path = string(tempname) + ".json";
fid = fopen(path, "wt");
assert(fid >= 0, "Unable to create temporary FRC catalog '%s'.", path);
fileCleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
count = fwrite(fid, jsonencode(catalog), "char");
assert(count > 0, "Unable to write temporary FRC catalog '%s'.", path);
end

function localDeleteIfPresent(path)
if isfile(path)
    delete(path);
end
end

function index = localEntryIndex(entries, entryId)
matches = false(numel(entries), 1);
for candidateIndex = 1:numel(entries)
    matches(candidateIndex) = ...
        string(localItem(entries, candidateIndex).id) == string(entryId);
end
indices = find(matches);
assert(numel(indices) == 1, ...
    "Expected one catalog entry with id '%s'.", entryId);
index = indices;
end

function sequence = localReplaceItem(sequence, index, value)
if iscell(sequence)
    sequence{index} = value;
else
    sequence(index) = value;
end
end

function item = localItem(sequence, index)
if iscell(sequence)
    item = sequence{index};
else
    item = sequence(index);
end
end
