function ok = testFRCFR2TDDAndRIB()
%TESTFRCFR2TDDANDRIB Exact FR2 TDD, CP timing, and RIB runtime regression.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

entries = [ ...
    "ul_g_fr2_a3_1_tdla30_300", "tdla30_300_low_1x2"; ...
    "ul_g_fr2_a5_1_tdla30_75_no_ptrs", ...
        "tdla30_75_low_1x2_no_ptrs"];
for index = 1:size(entries,1)
    setup = sixgr.conformance.runFRCPoint( ...
        entries(index,1), entries(index,2), ...
        "ValidateSetupOnly", true, ...
        "RequireExactStandardExecution", true, ...
        "RequireExactDataChannelExecution", true, ...
        "PrintTable", false, "Verbose", false);
    assert(logical(setup.StandardExecution.Exact) && ...
        logical(setup.DataChannelExecution.Exact));
    localAssertTDDWaveform(setup.SetupValidation.StandardWaveform);
    interface = setup.DataChannelExecution.Contract.TestInterface;
    assert(logical(interface.Exact) && interface.RIBCount == 2 && ...
        isequal(interface.RIBLabels(:), ["RIB-1"; "RIB-2"]) && ...
        isequal(double(interface.ReceiverBranchByRIB(:)), [1; 2]) && ...
        interface.ReferencePlane == "radiated_interface_boundary");
end

% One actual transport block is intentionally diagnostic, not a claim
% about the 70% throughput requirement. It proves that the configured
% reference plane and TDD schedule survive the real Tx/channel/Rx chain.
runtime = sixgr.conformance.runFRCPoint( ...
    entries(1,1), entries(1,2), ...
    "SNRGrid_dB", -2, "ExecutionProfile", "smoke", ...
    "MinTransportBlocks", 1, "MaxTransportBlocks", 1, ...
    "BatchSize", 1, "EvaluateSymmetricRegression", false, ...
    "RequireExactStandardExecution", true, ...
    "RequireExactDataChannelExecution", true, ...
    "PrintTable", false, "Verbose", false);
assert(height(runtime.Sweep) == 1 && runtime.Sweep.TransportBlocks == 1 && ...
    ~runtime.NormativePass && ~runtime.StatisticallyQualified);
detail = runtime.PointDetails{1};
localAssertTDDWaveform(detail.Propagation.StandardUplinkWaveform);
noise = detail.Noise;
assert(logical(noise.RuntimeRIBExact) && ...
    logical(noise.NoiseAppliedSeparatelyPerRIB) && ...
    logical(noise.EqualConfiguredVariancePerRIB) && ...
    noise.RIBCount == 2 && ...
    isequal(noise.RIBLabels(:), ["RIB-1"; "RIB-2"]) && ...
    noise.NumRxColumns == 2);
attempts = double(detail.TransportBlockAudit.Attempts(1));
assert(attempts >= 1 && attempts <= 4);
expectedSlots = [4 9 14 19];
assert(isequal(double(detail.TransportBlockAudit.AbsoluteSlotByAttempt( ...
    1,1:attempts)), ...
    expectedSlots(1:attempts)));

ok = true;
end

function localAssertTDDWaveform(waveform)
assert(logical(waveform.Materialized) && waveform.ContinuousSlotCount == 20);
assert(isequal(double(waveform.HARQOpportunitySlots(:).'), [4 9 14 19]));
assert(isequal(waveform.TDDSlotFormats(:), ["D"; "D"; "D"; "S"; "U"]));
assert(waveform.SpecialSlotDownlinkSymbols == 10 && ...
    waveform.SpecialSlotGuardSymbols == 2 && ...
    waveform.SpecialSlotUplinkSymbols == 2);
slotTable = waveform.SlotTable;
assert(isequal(double(slotTable.Slot(logical(slotTable.PUSCHMaterialized)).'), ...
    [4 9 14 19]));
assert(all(slotTable.TBSBits(~slotTable.PUSCHMaterialized) == 0) && ...
    all(slotTable.GBits(~slotTable.PUSCHMaterialized) == 0));
assert(waveform.InactiveSlotGridEnergy == 0 && ...
    waveform.ActiveSlotGridEnergy > 0);
samples = double(waveform.SamplesPerSlotBySlot(:).');
offsets = double(waveform.SampleOffsetBySlot(:).');
assert(numel(samples) == 20 && numel(unique(samples)) == 2 && ...
    isequal(offsets, [0 cumsum(samples(1:end-1))]) && ...
    sum(samples) == waveform.WaveformSize(1));
end
