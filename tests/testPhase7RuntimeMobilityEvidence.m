function ok = testPhase7RuntimeMobilityEvidence()
%TESTPHASE7RUNTIMEMOBILITYEVIDENCE Runtime slot traces must back 200 km/h mobility gates.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

cfg = struct();
cfg.frame_timing.slot_duration_ms = 0.5;
cfg.run_control.total_slots = 4;
cfg.frequency.center_frequency_hz = 4.0e9;
cfg.mobility.ue_speed_kmh = 200;
cfg.scenario.bs.height_m = 25;

traceT = localRuntimeTraceTable(cfg);
tracePath = fullfile(tmp, "reports", "csv", "live_rsrp_serving_trace.csv");
sixgr.analytics.writeAnalysisTable(tracePath, traceT);
sixgr.util.jsonWrite(fullfile(tmp, "reports", "json", "scenario_manifest.json"), struct("Fixture", "phase7_runtime_mobility"));

report = sixgr.analytics.buildPhase7ReadinessArtifacts(cfg, tmp);

for rel = [ ...
        "geometry/csv/trajectory_geometry.csv"
        "geometry/csv/ue_initial_positions.csv"
        "mobility/csv/trajectory_segment_table.csv"
        "mobility/csv/doppler_reconciliation.csv"
        "mobility/csv/pathloss_reconciliation.csv"
        "mobility/csv/propagation_delay_reconciliation.csv"
        "mobility/csv/channel_continuity_reconciliation.csv"]'
    assert(exist(fullfile(tmp, char(rel)), "file") == 2, "Missing runtime mobility evidence artifact: %s", rel);
end

traj = readtable(fullfile(tmp, "geometry", "csv", "trajectory_geometry.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
assert(height(traj) == 4, "Runtime trajectory geometry must publish one row per slot.");
assert(all(strcmp(string(traj.Status), "runtime_trace_complete")), ...
    "Runtime trajectory rows must identify complete slot-backed mobility evidence.");
assert(all(abs(double(traj.ExpectedDopplerHz) - 741.25) < 0.1), ...
    "Expected Doppler must prove the 200 km/h at 4 GHz operating point.");

delayT = readtable(fullfile(tmp, "mobility", "csv", "propagation_delay_reconciliation.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
assert(height(delayT) == 4 && all(localAsLogical(delayT.PropagationDelayReconciliationOk)), ...
    "Propagation delay reconciliation must stay non-empty and pass for every slot.");

continuityT = readtable(fullfile(tmp, "mobility", "csv", "channel_continuity_reconciliation.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
assert(height(continuityT) == 1 && localAsLogical(continuityT.ChannelStateContinuityOk(1)), ...
    "Channel continuity reconciliation must prove slot-by-slot runtime continuity.");

for name = ["FullTrajectoryExecutedOk","MobilityStateContinuousOk","LosStateModelOk", ...
        "PathlossReconciliationOk","ShadowFadingReconciliationOk","LargeScaleParameterReconciliationOk", ...
        "ChannelStateContinuityOk","DopplerReconciliationOk","PropagationDelayReconciliationOk"]
    assert(logical(report.Gates.(char(name))), ...
        "Expected runtime mobility gate %s to pass with complete slot evidence.", name);
end

ok = true;
end

function T = localRuntimeTraceTable(cfg)
slotDuration_s = double(cfg.frame_timing.slot_duration_ms) / 1e3;
speed_mps = double(cfg.mobility.ue_speed_kmh) / 3.6;
fcHz = double(cfg.frequency.center_frequency_hz);
c = 299792458;
bsPos = [0, 0, double(cfg.scenario.bs.height_m)];
basePathloss = 100;
shadow = 3;
o2i = 0;
pathloss = basePathloss + shadow + o2i;
appliedDoppler = speed_mps * fcHz / c;

rows = repmat(struct( ...
    "Slot", NaN, "Time_s", NaN, "UEID", NaN, "CellID", NaN, "ServingCell", NaN, ...
    "X_m", NaN, "Y_m", NaN, "Z_m", NaN, "Speed_kmh", NaN, "Speed_mps", NaN, ...
    "Heading_deg", NaN, "Heading_rad", NaN, ...
    "Distance2D_m", NaN, "Distance3D_m", NaN, "PropagationDelay_s", NaN, ...
    "RadialVelocity_mps", NaN, "ExpectedDopplerHz", NaN, "AppliedDopplerHz", NaN, "SignedDoppler_Hz", NaN, ...
    "BasePathloss_dB", NaN, "Pathloss_dB", NaN, "ShadowFading_dB", NaN, "O2I_dB", NaN, ...
    "LOSFlag", false, "LOSState", "", "PathlossModelSource", "", "PathlossComplianceStatus", "", ...
    "LOSProbabilitySource", "", "LOSComplianceStatus", "", "Status", ""), 4, 1);

for slot = 1:4
    t = double(slot - 1) * slotDuration_s;
    pos = [300 + speed_mps * t, 0, 1.5];
    d2d = hypot(pos(1) - bsPos(1), pos(2) - bsPos(2));
    d3d = norm(pos - bsPos);
    rows(slot) = struct( ...
        "Slot", double(slot), ...
        "Time_s", double(t), ...
        "UEID", 1, ...
        "CellID", 1, ...
        "ServingCell", 1, ...
        "X_m", double(pos(1)), ...
        "Y_m", double(pos(2)), ...
        "Z_m", double(pos(3)), ...
        "Speed_kmh", double(cfg.mobility.ue_speed_kmh), ...
        "Speed_mps", double(speed_mps), ...
        "Heading_deg", 0, ...
        "Heading_rad", 0, ...
        "Distance2D_m", double(d2d), ...
        "Distance3D_m", double(d3d), ...
        "PropagationDelay_s", double(d3d / c), ...
        "RadialVelocity_mps", double(speed_mps), ...
        "ExpectedDopplerHz", double(appliedDoppler), ...
        "AppliedDopplerHz", double(appliedDoppler), ...
        "SignedDoppler_Hz", double(appliedDoppler), ...
        "BasePathloss_dB", double(basePathloss), ...
        "Pathloss_dB", double(pathloss), ...
        "ShadowFading_dB", double(shadow), ...
        "O2I_dB", double(o2i), ...
        "LOSFlag", true, ...
        "LOSState", "LOS", ...
        "PathlossModelSource", "runtime_geometry_fixture", ...
        "PathlossComplianceStatus", "reconciled_fixture", ...
        "LOSProbabilitySource", "runtime_geometry_fixture", ...
        "LOSComplianceStatus", "reconciled_fixture", ...
        "Status", "runtime_trace_complete");
end

T = struct2table(rows, "AsArray", true);
end

function tf = localAsLogical(value)
token = lower(strtrim(string(value)));
tf = token == "1" | token == "true" | token == "yes" | token == "pass" | token == "passed" | token == "ok";
end
