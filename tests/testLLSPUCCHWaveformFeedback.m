function localAssertTypedError(f, expectedId)
threw = false;
try
    f();
catch ME
    threw = true;
    assert(strcmp(string(ME.identifier), string(expectedId)), ...
        "Expected %s, received %s.", expectedId, ME.identifier);
end
assert(threw, "Expected typed error %s.", expectedId);
end
