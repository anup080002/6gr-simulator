function ok = testLLSPUCCHWaveformFeedback()
%TESTLLSPUCCHWAVEFORMFEEDBACK Verify waveform-backed PUCCH feedback trial integrity.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.snr_dB = 20;
cfg.run.noiseOperatingMode = "configured_snr_anchor_after_large_scale_gain";
cfg.run.interferenceExecutionMode = "none";

multiUser = struct( ...
    "Enabled", true, ...
    "NumUsers", 1, ...
    "RNTIStart", 320, ...
    "ExecutionModel", "slot_coupled_truth");
cfg.phy.rnti = double(multiUser.RNTIStart);

trial = sixgr.link.runPUCCHWaveformTrial(cfg, ...
    "ExpectedUCIBits", int8(1), ...
    "SNR_dB", 20, ...
    "Format", sixgr.util.structGet(cfg, "phy.pucch.format", 2), ...
    "RNTI", double(multiUser.RNTIStart));

assert(isstruct(trial), ...
    "Waveform-backed PUCCH helper must return a runtime trial struct.");
assert(all(cellfun(@(name) isfield(trial, name), {"Ok","ExpectedBits","DecodedBits","BitsCompared","BitErrors","UCIContentMatch","CRCApplicable","ChannelModel","ConfiguredSNR_dB","AppliedAWGNSNR_dB","RequestedFormat","ResolvedFormat","FormatAdapted","FormatAdaptationReason","ControlResourceValidity","CrashSource","CrashMessage","DetectionMetric","Notes"})), ...
    "Waveform-backed PUCCH trials must expose direct runtime evidence fields.");
assert(numel(trial.ExpectedBits) == 1, ...
    "PUCCH waveform trial must preserve the one-bit HARQ payload in this focused check.");
assert(contains(char(string(trial.Notes)), "Waveform-backed PUCCH"), ...
    "Waveform-backed PUCCH helper must disclose its active PHY path in the notes.");
assert(isfinite(double(trial.ConfiguredSNR_dB)), ...
    "Waveform-backed PUCCH trials must expose the configured runtime SNR reference.");
assert(~logical(trial.CRCApplicable) && logical(trial.UCIContentMatch), ...
    "Waveform-backed PUCCH trials must distinguish UCI payload match from CRC semantics.");
assert(~isempty(char(string(trial.ChannelModel))), ...
    "Waveform-backed PUCCH trials must expose the active channel model.");
assert(double(trial.RequestedFormat) == 2 && double(trial.ResolvedFormat) == 1 && logical(trial.FormatAdapted), ...
    "Waveform-backed PUCCH trials must disclose when the configured browser format is adapted to a payload-compatible runtime format.");
assert(strlength(string(trial.FormatAdaptationReason)) > 0 && logical(trial.ControlResourceValidity) && ...
    strlength(string(trial.CrashSource)) == 0 && strlength(string(trial.CrashMessage)) == 0, ...
    "Waveform-backed PUCCH trials must disclose format-adaptation reasoning and keep crash provenance empty on success.");

cfg.run.interferenceExecutionMode = "full_per_link_channel_waveform_sum";
cfg.channel.snr_dB = 40;
cfg.scenario.nUE = 2;
cfg.scenario.ue.nUE = 2;
cfg.phy.rnti = 320;
multiUserRuntime = struct( ...
    "Enabled", true, ...
    "NumUsers", 2, ...
    "RNTIStart", 320, ...
    "ExecutionModel", "slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize(cfg, fullfile(tmp, "runtime"), multiUserRuntime, struct(), 1);
state.CurrentServingIdx(1:2) = 1;
state.CurrentServingMetric_dBm(1:2) = -70;
state.LargeScaleState.BeamIndex = ones(2, 1);
state.LargeScaleState.BeamGain_dB = zeros(2, 1);
state.LargeScaleState.RxPower_dBm = -70 * ones(2, 1);
state.LargeScaleState.BasePathloss_dB = 100 * ones(2, 1);
state.LargeScaleState.Pathloss_dB = 100 * ones(2, 1);
state.LargeScaleState.Shadow_dB = zeros(2, 1);
state.LargeScaleState.O2I_dB = zeros(2, 1);
state.CurrentSlot = 5;
state.CurrentFrame = 1;
state.CurrentSNR_dB = 40;

feedbackRows = repmat(localEmptyFeedbackRow(), 2, 1);
for ueIdx = 1:2
    feedbackRows(ueIdx).Direction = "DL";
    feedbackRows(ueIdx).UEIndex = ueIdx;
    feedbackRows(ueIdx).RNTI = double(multiUserRuntime.RNTIStart + ueIdx - 1);
    feedbackRows(ueIdx).HarqID = ueIdx - 1;
    feedbackRows(ueIdx).SourceSlot = 1;
    feedbackRows(ueIdx).DueSlot = 5;
    feedbackRows(ueIdx).Ack = true;
    feedbackRows(ueIdx).CurrentDecodeOK = true;
    feedbackRows(ueIdx).CombinedDecodeOK = true;
    feedbackRows(ueIdx).ServingCell = 1;
    feedbackRows(ueIdx).BaseStationID = 1;
    feedbackRows(ueIdx).TBSBits = 5376;
    feedbackRows(ueIdx).UCIBitCount = 1;
    seedRow = struct2table(feedbackRows(ueIdx), "AsArray", true);
    resource = sixgr.truth.CoupledTruthRuntime.resolvePUCCHResourceAssignmentRuntime(state, seedRow);
    feedbackRows(ueIdx).RequestedFormat = double(resource.RequestedFormat);
    feedbackRows(ueIdx).ResolvedFormat = double(resource.ResolvedFormat);
    feedbackRows(ueIdx).PUCCHResourceId = char(string(resource.ResourceId));
    feedbackRows(ueIdx).PUCCHPRBStart = double(resource.PRBStart);
    feedbackRows(ueIdx).PUCCHPRBCount = double(resource.PRBCount);
    feedbackRows(ueIdx).PUCCHSymbolStart = double(resource.SymbolStart);
    feedbackRows(ueIdx).PUCCHNumSymbols = double(resource.NumSymbols);
    feedbackRows(ueIdx).UCIType = char(string(resource.UCIType));
    feedbackRows(ueIdx).ControlResourceSource = char(string(resource.ControlResourceSource));
end
state.PendingFeedbackTable = struct2table(feedbackRows, "AsArray", true);
for ueIdx = 1:2
    state = sixgr.truth.CoupledTruthRuntime.schedulePUCCHGrantRuntime(state, state.PendingFeedbackTable(ueIdx, :));
end
assert(istable(state.PUCCHGrantTraceTable) && height(state.PUCCHGrantTraceTable) == 2, ...
    "Focused PUCCH runtime setup must create explicit scheduled PUCCH grant/resource rows.");
grantRow = state.PUCCHGrantTraceTable(1, :);
assert(strlength(string(grantRow.PUCCHGrantId(1))) > 0 && ...
    strcmpi(char(string(grantRow.PUCCHGrantState(1))), "scheduled_pending_execution") && ...
    logical(grantRow.GrantScheduledFlag(1)) && ~logical(grantRow.GrantExecutedFlag(1)), ...
    "Scheduled PUCCH grant rows must expose explicit schedule state before waveform execution.");
assert(double(grantRow.UEID(1)) == 1 && double(grantRow.BaseStationID(1)) == 1 && ...
    strlength(string(grantRow.PUCCHResourceId(1))) > 0 && strcmpi(char(string(grantRow.UCIType(1))), "harq_ack"), ...
    "Scheduled PUCCH grant rows must expose UE/base-station identity, resource identity, and UCI content type.");

stateNoPeer = state;
stateNoPeer.PendingFeedbackTable = state.PendingFeedbackTable(1, :);
[stateNoPeer, observed] = sixgr.truth.CoupledTruthRuntime.observePUCCHFeedbackRuntime(stateNoPeer, stateNoPeer.PUCCHGrantTraceTable(1, :));
if logical(observed.DecodeOk)
    assert(logical(observed.ObservedAck) && isfinite(double(stateNoPeer.LastSuccessfulPUCCHSlotByUE(1))) && ...
        double(stateNoPeer.LastSuccessfulPUCCHSlotByUE(1)) == 5, ...
        "Successful coupled PUCCH observation must update the last-success runtime state.");
else
    assert(double(stateNoPeer.PUCCHFailureCount(1)) >= 1, ...
        "Failed coupled PUCCH observation must update the runtime failure state.");
end

[state, observedWithPeer] = sixgr.truth.CoupledTruthRuntime.observePUCCHFeedbackRuntime(state, state.PUCCHGrantTraceTable(1, :)); %#ok<NASGU>
assert(istable(state.ControlTrials.PUCCH) && height(state.ControlTrials.PUCCH) >= 1, ...
    "Active coupled PUCCH observation must append a runtime-backed control trial row.");
row = state.ControlTrials.PUCCH(end, :);
grantIdx = find(strcmp(string(state.PUCCHGrantTraceTable.PUCCHGrantId), string(row.PUCCHGrantId(1))), 1, "last");
assert(~isempty(grantIdx), ...
    "Observed PUCCH trial rows must point at an existing explicit runtime PUCCH grant row.");
grantObserved = state.PUCCHGrantTraceTable(grantIdx, :);
assert(strlength(string(row.PUCCHResourceId(1))) > 0 && strcmpi(char(string(row.ControlResourceSource(1))), "runtime_deterministic_pucch_resource_assignment"), ...
    "Coupled PUCCH rows must expose the runtime resource identity and source.");
assert(logical(row.RuntimeStateUpdated(1)) && strcmpi(char(string(row.RuntimeStateConsumer(1))), "HARQEntity.onFeedback"), ...
    "Coupled PUCCH rows must disclose the runtime state consumer.");
assert(strlength(string(row.PUCCHGrantId(1))) > 0 && double(row.UEID(1)) == double(row.UEIndex(1)) && logical(row.ControlStateChanged(1)) == logical(row.PUCCHDecodeOk(1)), ...
    "Coupled PUCCH rows must link back to the scheduled grant row and disclose whether control state changed.");
assert(logical(row.ControlResourceValidity(1)) && ...
    logical(row.StateChangeApplied(1)) == logical(row.PUCCHDecodeOk(1)) && ...
    strlength(string(row.FormatAdaptationReason(1))) > 0, ...
    "Coupled PUCCH rows must disclose whether feedback state changes were applied and why format adaptation occurred.");
assert(~logical(row.Crash(1)) && isfinite(double(row.RequestedFormat(1))) && isfinite(double(row.ResolvedFormat(1))) && ...
    double(row.RequestedFormat(1)) == 2 && double(row.ResolvedFormat(1)) == 1, ...
    "Coupled PUCCH rows must preserve the real requested and runtime-resolved PUCCH formats even for one-bit HARQ UCI.");
assert(strlength(string(row.CrashSource(1))) == 0 && strlength(string(row.CrashMessage(1))) == 0, ...
    "Coupled PUCCH rows must keep crash provenance empty on successful runtime observations.");
assert(double(row.InterferenceContributorCount(1)) >= 1 && ~strcmpi(char(string(row.InterferenceMode(1))), "none"), ...
    "Coupled PUCCH rows must disclose active same-slot interference when peer feedback users are present.");
assert(strcmpi(char(string(grantObserved.PUCCHGrantId(1))), char(string(row.PUCCHGrantId(1)))) && ...
    logical(grantObserved.GrantExecutedFlag(1)) && ...
    logical(grantObserved.RuntimeStateUpdated(1)) && ...
    strcmpi(char(string(grantObserved.RuntimeStateConsumer(1))), "HARQEntity.onFeedback") && ...
    strcmpi(char(string(grantObserved.InterferenceMode(1))), char(string(row.InterferenceMode(1)))), ...
    "Executed PUCCH grant rows must preserve truthful execution/interference/runtime-consumer evidence.");

ok = true;
end

function row = localEmptyFeedbackRow()
row = struct( ...
    "Direction", "", "UEIndex", NaN, "RNTI", NaN, ...
    "HarqID", NaN, "SourceSlot", NaN, "DueSlot", NaN, "Ack", false, ...
    "CurrentDecodeOK", false, "CombinedDecodeOK", false, ...
    "ServingCell", NaN, "BaseStationID", NaN, "TBSBits", NaN, "UCIBitCount", NaN, ...
    "RequestedFormat", NaN, "ResolvedFormat", NaN, "PUCCHResourceId", "", ...
    "PUCCHPRBStart", NaN, "PUCCHPRBCount", NaN, ...
    "PUCCHSymbolStart", NaN, "PUCCHNumSymbols", NaN, ...
    "UCIType", "", "ControlResourceSource", "", "PUCCHGrantId", "", "Processed", false);
end
