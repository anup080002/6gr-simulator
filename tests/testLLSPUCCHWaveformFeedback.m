combinedPart1 = int8([1; 0]);
% This runtime supports the configured periodic CSI Part 1 obligation.
% Separately coded Part 2 has its own fail-closed resource-budget guard and
% is not flattened into this focused combined-PUCCH fixture.
combinedPart2 = int8(zeros(0,1));
combinedCSI = struct( ...
    "ReportIdentity", "csi:combined:slot5:ue1", ...
    "CSIPart1BitsToken", char(sixgr.runtime.RawCSVArrayCodec.encode(combinedPart1)), ...
    "CSIPart2BitsToken", char(sixgr.runtime.RawCSVArrayCodec.encode(combinedPart2)));
