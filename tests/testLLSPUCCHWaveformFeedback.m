function ok = testLLSPUCCHWaveformFeedback()
%TESTLLSPUCCHWAVEFORMFEEDBACK Verify waveform-backed PUCCH feedback trial integrity.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd, "simulator", "configs", "scenarios", "lls_100mhz_tdlc_bidirectional_truth.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.snr_dB = 20;
cfg.phy.pucch.format = 2;
cfg.run.noiseOperatingMode = "receiver_noise_figure_thermal_noise";
cfg.run.interferenceExecutionMode = "none";

multiUser = struct( ...
    "Enabled", true, ...
    "NumUsers", 1, ...
    "RNTIStart", 320, ...
    "ExecutionModel", "slot_coupled_truth");
cfg.phy.rnti = double(multiUser.RNTIStart);

trial = sixgr.link.runPUCCHWaveformTrial(cfg, ...
    "ExpectedUCIBits", int8(1), ...
    "SNR_dB", 20, ...
    "Format", sixgr.util.structGet(cfg, "phy.pucch.format", 2), ...
    "RNTI", double(multiUser.RNTIStart));
trialNack = sixgr.link.runPUCCHWaveformTrial(cfg, ...
    "ExpectedUCIBits", int8(0), ...
    "SNR_dB", 20, ...
    "Format", sixgr.util.structGet(cfg, "phy.pucch.format", 2), ...
    "RNTI", double(multiUser.RNTIStart));
trialCSI = sixgr.link.runPUCCHWaveformTrial(cfg, ...
    "ExpectedUCIBits", int8(mod((0:19).', 2)), ...
    "SNR_dB", 30, ...
    "Format", 2, ...
    "RNTI", double(multiUser.RNTIStart));

assert(isstruct(trial), ...
    "Waveform-backed PUCCH helper must return a runtime trial struct.");
assert(all(cellfun(@(name) isfield(trial, name), {"Ok","ExpectedBits","DecodedBits","ExpectedBitCount","DecodedBitCount","UCIExpectedBitVector","UCIDecodedBitVector","UCIBitErrorVector","UCICodedBitCount","UCICRCBitCount","UCICRCApplicable","BitsCompared","BitErrors","UCIContentMatch","CRCApplicable","CRCOutcome","DetectionOutcome","ChannelModel","ConfiguredSNR_dB","AppliedAWGNSNR_dB","RequestedFormat","ResolvedFormat","FormatAdapted","FormatAdaptationReason","ControlResourceValidity","CrashSource","CrashMessage","DetectionMetric","NoiseVariance","NoiseVarStatus","NoiseVarSource","NoiseVarReason","ReceiverUsable","DetectionAttempted","DetectionUsable","FailureReason","ReceiverHestSINRApplicable","ReceiverHestSINRValueRole","ReceiverHestSINRValueStatus","MeasuredTrialSINRValueRole","MeasuredTrialSINRValueStatus","SINRValueStatus","SINRValueDefinition","Notes"})), ...
    "Waveform-backed PUCCH trials must expose direct runtime evidence fields.");
assert(numel(trial.ExpectedBits) == 1, ...
    "PUCCH waveform trial must preserve the one-bit HARQ payload in this focused check.");
assert(contains(char(string(trial.Notes)), "Waveform-backed PUCCH"), ...
    "Waveform-backed PUCCH helper must disclose its active PHY path in the notes.");
assert(isfinite(double(trial.ConfiguredSNR_dB)), ...
    "Waveform-backed PUCCH trials must expose the configured runtime SNR reference.");
assert(~logical(trial.CRCApplicable) && logical(trial.UCIContentMatch), ...
    "Waveform-backed PUCCH trials must distinguish UCI payload match from CRC semantics.");
assert(double(trial.ExpectedBitCount) == 1 && double(trial.DecodedBitCount) == 1 && ...
    double(trial.UCICodedBitCount) == 0 && double(trial.UCICRCBitCount) == 0 && ...
    ~logical(trial.UCICRCApplicable) && strlength(string(trial.UCIExpectedBitVector)) > 0 && ...
    strlength(string(trial.UCIDecodedBitVector)) > 0 && strlength(string(trial.UCIBitErrorVector)) > 0, ...
    "One-bit PUCCH HARQ/SR rows must export payload evidence and zero UCI CRC bits.");
assert(logical(trialCSI.Ok) && logical(trialCSI.CRCApplicable) && logical(trialCSI.UCICRCApplicable) && ...
    double(trialCSI.ExpectedBitCount) == 20 && double(trialCSI.DecodedBitCount) == 20 && ...
    double(trialCSI.UCICRCBitCount) == 6 && double(trialCSI.UCICodedBitCount) > double(trialCSI.ExpectedBitCount) && ...
    logical(trialCSI.ReceiverHestSINRApplicable) && isfinite(double(trialCSI.ReceiverHestSINR_dB)), ...
    "Format-2 CSI PUCCH rows must carry real encoded-UCI, CRC, and DMRS/Hest receiver evidence.");
assert(logical(trialNack.Ok) && logical(trialNack.DetectionUsable) && ...
    double(trialNack.BitsCompared) == 1 && double(trialNack.BitErrors) == 0 && ...
    double(trialNack.DecodedBits(1)) == 0 && isfinite(double(trialNack.DetectionMetric)), ...
    "PUCCH F2-to-F1 HARQ NACK payloads must decode as real zero bits, not DTX/unavailable rows.");
assert(strcmpi(char(string(trial.CRCOutcome)), "not_applicable") && strcmpi(char(string(trial.DetectionOutcome)), "detected"), ...
    "Waveform-backed PUCCH trials must export explicit CRC and detection outcomes without pretending CRC applies.");
assert(~isempty(char(string(trial.ChannelModel))), ...
    "Waveform-backed PUCCH trials must expose the active channel model.");
assert(double(trial.RequestedFormat) == 2 && double(trial.ResolvedFormat) == 1 && logical(trial.FormatAdapted), ...
    "Waveform-backed PUCCH trials must disclose when the configured browser format is adapted to a payload-compatible runtime format.");
assert(strlength(string(trial.FormatAdaptationReason)) > 0 && logical(trial.ControlResourceValidity) && ...
    strlength(string(trial.CrashSource)) == 0 && strlength(string(trial.CrashMessage)) == 0, ...
    "Waveform-backed PUCCH trials must disclose format-adaptation reasoning and keep crash provenance empty on success.");
assert(strcmpi(char(string(trial.NoiseVarStatus)), "OK") && strlength(string(trial.NoiseVarSource)) > 0 && ...
    logical(trial.ReceiverUsable) && logical(trial.DetectionAttempted) && logical(trial.DetectionUsable) && ...
    (~isfinite(double(trial.NoiseVariance)) || abs(double(trial.NoiseVariance) - 1e-10) > 1e-18), ...
    "Waveform-backed PUCCH trials must expose valid noise-variance provenance without the legacy near-zero fallback.");
if isfinite(double(trial.MeasuredTrialSINR_dB))
    assert(strcmpi(char(string(trial.MeasuredTrialSINRValueRole)), "measured") && ...
        strcmpi(char(string(trial.MeasuredTrialSINRValueStatus)), "OK") && ...
        strcmpi(char(string(trial.SINRValueRole)), "measured"), ...
        "PUCCH waveform trials must label real measured-trial SINR as measured, not estimated.");
else
    assert(strcmpi(char(string(trial.MeasuredTrialSINRValueStatus)), "unavailable") && ...
        ~strcmpi(char(string(trial.SINRValueRole)), "measured"), ...
        "PUCCH waveform trials must keep MeasuredTrialSINR unavailable when only fallback SINR exists.");
end

cfg.run.interferenceExecutionMode = "full_per_link_channel_waveform_sum";
cfg.channel.snr_dB = 40;
cfg.scenario.nUE = 2;
cfg.scenario.ue.nUE = 2;
cfg.phy.rnti = 320;
multiUserRuntime = struct( ...
    "Enabled", true, ...
    "NumUsers", 2, ...
    "RNTIStart", 320, ...
    "ExecutionModel", "slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize(cfg, fullfile(tmp, "runtime"), multiUserRuntime, struct(), 1);
state.CurrentServingIdx(1:2) = 1;
state.CurrentServingMetric_dBm(1:2) = -70;
state.LargeScaleState.BeamIndex = ones(2, 1);
state.LargeScaleState.BeamGain_dB = zeros(2, 1);
state.LargeScaleState.RxPower_dBm = -70 * ones(2, 1);
state.LargeScaleState.BasePathloss_dB = 100 * ones(2, 1);
state.LargeScaleState.Pathloss_dB = 100 * ones(2, 1);
state.LargeScaleState.Shadow_dB = zeros(2, 1);
state.LargeScaleState.O2I_dB = zeros(2, 1);
state.CurrentSlot = 5;
state.CurrentFrame = 1;
state.CurrentSNR_dB = 40;

stateTdd = state;
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "frequency.duplex_mode", "TDD");
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "phy.duplex.mode", "TDD");
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "global_radio_scope.duplex_mode", "TDD");
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "frame_timing.tdd_pattern", "DDDSU");
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "phy.duplex.tddPattern", "DDDSU");
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "frame_timing.symbols_per_slot", 14);
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "frame_timing.special_slot_downlink_symbols", 10);
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "frame_timing.ul_dl_guard_symbols", 3);
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "frame_timing.special_slot_uplink_symbols", 1);
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "phy.duplex.specialSlot.numDLSymbols", 10);
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "phy.duplex.specialSlot.numGuardSymbols", 3);
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "phy.duplex.specialSlot.numULSymbols", 1);
stateTdd.CfgMobility = sixgr.util.structSet(stateTdd.CfgMobility, "phy.pucch.format", 2);
stateTdd.HARQFeedbackSlots = 4;
dueSlot = sixgr.truth.CoupledTruthRuntime.resolveHARQFeedbackDueSlotRuntime(stateTdd, 7, 1);
assert(double(dueSlot) == 15, ...
    "DDDSU HARQ feedback must skip DL-only slots and special slots without enough UL symbols for the resolved PUCCH format.");
specialFeedback = localEmptyFeedbackRow();
specialFeedback.Direction = "DL";
specialFeedback.UEIndex = 1;
specialFeedback.RNTI = double(multiUserRuntime.RNTIStart);
specialFeedback.HarqID = 0;
specialFeedback.SourceSlot = 7;
specialFeedback.DueSlot = 14;
specialFeedback.Ack = true;
specialFeedback.ServingCell = 1;
specialFeedback.BaseStationID = 1;
specialFeedback.UCIBitCount = 1;
specialResource = sixgr.truth.CoupledTruthRuntime.resolvePUCCHResourceAssignmentRuntime( ...
    stateTdd, struct2table(specialFeedback, "AsArray", true));
assert(~logical(specialResource.ControlResourceValidity), ...
    "PUCCH resource assignment must not mark a one-symbol special slot as valid for four-symbol HARQ-ACK feedback.");
validFeedback = specialFeedback;
validFeedback.DueSlot = dueSlot;
validResource = sixgr.truth.CoupledTruthRuntime.resolvePUCCHResourceAssignmentRuntime( ...
    stateTdd, struct2table(validFeedback, "AsArray", true));
assert(logical(validResource.ControlResourceValidity) && double(validResource.SymbolStart) == 10 && double(validResource.NumSymbols) == 4, ...
    "Resolved HARQ feedback due slot must produce a valid full-UL PUCCH resource for one-bit HARQ-ACK.");

feedbackRows = repmat(localEmptyFeedbackRow(), 2, 1);
for ueIdx = 1:2
    feedbackRows(ueIdx).Direction = "DL";
    feedbackRows(ueIdx).UEIndex = ueIdx;
    feedbackRows(ueIdx).RNTI = double(multiUserRuntime.RNTIStart + ueIdx - 1);
    feedbackRows(ueIdx).HarqID = ueIdx - 1;
    feedbackRows(ueIdx).SourceSlot = 1;
    feedbackRows(ueIdx).DueSlot = 5;
    feedbackRows(ueIdx).Ack = true;
    feedbackRows(ueIdx).CurrentDecodeOK = true;
    feedbackRows(ueIdx).CombinedDecodeOK = true;
    feedbackRows(ueIdx).ServingCell = 1;
    feedbackRows(ueIdx).BaseStationID = 1;
    feedbackRows(ueIdx).TBSBits = 5376;
    feedbackRows(ueIdx).UCIBitCount = 1;
    seedRow = struct2table(feedbackRows(ueIdx), "AsArray", true);
    resource = sixgr.truth.CoupledTruthRuntime.resolvePUCCHResourceAssignmentRuntime(state, seedRow);
    feedbackRows(ueIdx).RequestedFormat = double(resource.RequestedFormat);
    feedbackRows(ueIdx).ResolvedFormat = double(resource.ResolvedFormat);
    feedbackRows(ueIdx).PUCCHResourceId = char(string(resource.ResourceId));
    feedbackRows(ueIdx).PUCCHPRBStart = double(resource.PRBStart);
    feedbackRows(ueIdx).PUCCHPRBCount = double(resource.PRBCount);
    feedbackRows(ueIdx).PUCCHSymbolStart = double(resource.SymbolStart);
    feedbackRows(ueIdx).PUCCHNumSymbols = double(resource.NumSymbols);
    feedbackRows(ueIdx).UCIType = char(string(resource.UCIType));
    feedbackRows(ueIdx).ControlResourceSource = char(string(resource.ControlResourceSource));
end
state.PendingFeedbackTable = struct2table(feedbackRows, "AsArray", true);
for ueIdx = 1:2
    state = sixgr.truth.CoupledTruthRuntime.schedulePUCCHGrantRuntime(state, state.PendingFeedbackTable(ueIdx, :));
end
assert(istable(state.PUCCHGrantTraceTable) && height(state.PUCCHGrantTraceTable) == 2, ...
    "Focused PUCCH runtime setup must create explicit scheduled PUCCH grant/resource rows.");
grantRow = state.PUCCHGrantTraceTable(1, :);
assert(strlength(string(grantRow.PUCCHGrantId(1))) > 0 && ...
    strcmpi(char(string(grantRow.PUCCHGrantState(1))), "scheduled_pending_execution") && ...
    logical(grantRow.GrantScheduledFlag(1)) && ~logical(grantRow.GrantExecutedFlag(1)), ...
    "Scheduled PUCCH grant rows must expose explicit schedule state before waveform execution.");
assert(double(grantRow.UEID(1)) == 1 && double(grantRow.BaseStationID(1)) == 1 && ...
    strlength(string(grantRow.PUCCHResourceId(1))) > 0 && strcmpi(char(string(grantRow.UCIType(1))), "harq_ack"), ...
    "Scheduled PUCCH grant rows must expose UE/base-station identity, resource identity, and UCI content type.");

duePUCCHUEs = sixgr.truth.CoupledTruthRuntime.pucchFeedbackDueUEsRuntime(state, 5);
assert(isequal(duePUCCHUEs(:), [1; 2]), ...
    "Runtime must expose UEs with same-slot HARQ-ACK PUCCH so UL scheduling can choose non-colliding PUSCH candidates.");

collisionGrants = repmat(struct( ...
    "Direction", "UL", "UEIndex", NaN, "RNTI", NaN, ...
    "Slot", 5, "ScheduledAbsoluteSlot", 5, "GrantReason", "newtx"), 3, 1);
for gi = 1:3
    collisionGrants(gi).UEIndex = double(gi);
    collisionGrants(gi).RNTI = double(multiUserRuntime.RNTIStart + gi - 1);
end
[filteredCollisionGrants, blockedPUSCH] = sixgr.truth.CoupledTruthRuntime.excludeULGrantsCollidingWithPUCCHRuntime( ...
    state, collisionGrants, 5);
assert(numel(filteredCollisionGrants) == 1 && double(filteredCollisionGrants(1).UEIndex) == 3 && ...
    istable(blockedPUSCH) && height(blockedPUSCH) == 2 && ...
    all(strcmpi(string(blockedPUSCH.Reason), "harq_ack_pucch_due_same_slot_same_ue")), ...
    "UL scheduler must not queue standalone PUSCH for UEs with same-slot HARQ-ACK PUCCH when UCI-on-PUSCH is not implemented.");
[otherSlotGrants, otherSlotBlocked] = sixgr.truth.CoupledTruthRuntime.excludeULGrantsCollidingWithPUCCHRuntime( ...
    state, collisionGrants, 6);
assert(numel(otherSlotGrants) == 3 && istable(otherSlotBlocked) && isempty(otherSlotBlocked), ...
    "PUCCH collision guard must preserve non-colliding future UL grants.");

stateNoPeer = state;
stateNoPeer.PendingFeedbackTable = state.PendingFeedbackTable(1, :);
[stateNoPeer, observed] = sixgr.truth.CoupledTruthRuntime.observePUCCHFeedbackRuntime(stateNoPeer, stateNoPeer.PUCCHGrantTraceTable(1, :));
if logical(observed.DecodeOk)
    assert(logical(observed.ObservedAck) && isfinite(double(stateNoPeer.LastSuccessfulPUCCHSlotByUE(1))) && ...
        double(stateNoPeer.LastSuccessfulPUCCHSlotByUE(1)) == 5, ...
        "Successful coupled PUCCH observation must update the last-success runtime state.");
else
    assert(double(stateNoPeer.PUCCHFailureCount(1)) >= 1, ...
        "Failed coupled PUCCH observation must update the runtime failure state.");
end

[state, observedWithPeer] = sixgr.truth.CoupledTruthRuntime.observePUCCHFeedbackRuntime(state, state.PUCCHGrantTraceTable(1, :)); %#ok<NASGU>
assert(istable(state.ControlTrials.PUCCH) && height(state.ControlTrials.PUCCH) >= 1, ...
    "Active coupled PUCCH observation must append a runtime-backed control trial row.");
row = state.ControlTrials.PUCCH(end, :);
grantIdx = find(strcmp(string(state.PUCCHGrantTraceTable.PUCCHGrantId), string(row.PUCCHGrantId(1))), 1, "last");
assert(~isempty(grantIdx), ...
    "Observed PUCCH trial rows must point at an existing explicit runtime PUCCH grant row.");
grantObserved = state.PUCCHGrantTraceTable(grantIdx, :);
assert(strlength(string(row.PUCCHResourceId(1))) > 0 && ...
    strcmpi(char(string(row.ControlResourceSource(1))), "runtime_deterministic_pucch_resource_assignment_tdd_ul_symbol_checked"), ...
    "Coupled PUCCH rows must expose the runtime resource identity and TDD-checked source.");
assert(all(ismember(["NoiseVariance","NoiseVarStatus","NoiseVarSource","NoiseVarReason","NoiseVarStrictFailure", ...
    "ReceiverUsable","DetectionAttempted","DetectionUsable","FailureReason","ExpectedBitCount", ...
    "DecodedBitCount","UCIExpectedBitVector","UCIDecodedBitVector","UCIBitErrorVector", ...
    "UCICodedBitCount","UCICRCBitCount","UCICRCApplicable","ReceiverHestSINRApplicable"], string(state.ControlTrials.PUCCH.Properties.VariableNames))), ...
    "Coupled PUCCH runtime tables must carry explicit noise-variance and receiver-availability provenance.");
assert(strcmpi(char(string(row.NoiseVarStatus(1))), "OK") && strlength(string(row.NoiseVarSource(1))) > 0, ...
    "Coupled PUCCH rows must preserve the active receiver noise-variance provenance.");
assert(~logical(row.CRCApplicable(1)) && isnan(double(row.CRCPass(1))) && ...
    strcmpi(char(string(row.CRCOutcome(1))), "not_applicable"), ...
    "Coupled PUCCH rows must keep CRCPass unavailable when CRC does not apply.");
assert(double(row.ExpectedBitCount(1)) == 1 && double(row.DecodedBitCount(1)) == 1 && ...
    double(row.UCICodedBitCount(1)) == 0 && double(row.UCICRCBitCount(1)) == 0 && ...
    ~logical(row.UCICRCApplicable(1)) && ...
    logical(row.ReceiverHestSINRApplicable(1)) == (double(row.PUCCHDMRSRECount(1)) > 0), ...
    "Coupled one-bit PUCCH rows must expose payload evidence, zero CRC bits, and DMRS-driven Hest applicability.");
if logical(row.DetectionUsable(1))
    expectedOutcome = ternaryDetectionOutcome(logical(row.UCIContentMatch(1)));
    assert(strcmpi(char(string(row.DetectionOutcome(1))), expectedOutcome), ...
        "Coupled PUCCH rows must export a detection outcome that matches the UCI content result.");
else
    assert(strcmpi(char(string(row.DetectionOutcome(1))), "unavailable"), ...
        "Coupled PUCCH rows must mark detection outcome unavailable when the runtime detection is unusable.");
end
assert(logical(row.RuntimeStateUpdated(1)) && strcmpi(char(string(row.RuntimeStateConsumer(1))), "HARQEntity.onFeedback"), ...
    "Coupled PUCCH rows must disclose the runtime state consumer.");
assert(strlength(string(row.PUCCHGrantId(1))) > 0 && double(row.UEID(1)) == double(row.UEIndex(1)) && logical(row.ControlStateChanged(1)) == logical(row.PUCCHDecodeOk(1)), ...
    "Coupled PUCCH rows must link back to the scheduled grant row and disclose whether control state changed.");
assert(logical(row.ControlResourceValidity(1)) && ...
    logical(row.StateChangeApplied(1)) == logical(row.PUCCHDecodeOk(1)) && ...
    strlength(string(row.FormatAdaptationReason(1))) > 0, ...
    "Coupled PUCCH rows must disclose whether feedback state changes were applied and why format adaptation occurred.");
assert(~logical(row.Crash(1)) && isfinite(double(row.RequestedFormat(1))) && isfinite(double(row.ResolvedFormat(1))) && ...
    double(row.RequestedFormat(1)) == 2 && double(row.ResolvedFormat(1)) == 1, ...
    "Coupled PUCCH rows must preserve the real requested and runtime-resolved PUCCH formats even for one-bit HARQ UCI.");
assert(strlength(string(row.CrashSource(1))) == 0 && strlength(string(row.CrashMessage(1))) == 0, ...
    "Coupled PUCCH rows must keep crash provenance empty on successful runtime observations.");
assert(double(row.InterferenceContributorCount(1)) == 0 && strcmpi(char(string(row.InterferenceMode(1))), "none"), ...
    "Coupled PUCCH rows must not synthesize same-slot interference from peer PUCCH grants on orthogonal PRB resources.");
assert(strcmpi(char(string(grantObserved.PUCCHGrantId(1))), char(string(row.PUCCHGrantId(1)))) && ...
    logical(grantObserved.GrantExecutedFlag(1)) && ...
    logical(grantObserved.RuntimeStateUpdated(1)) && ...
    strcmpi(char(string(grantObserved.RuntimeStateConsumer(1))), "HARQEntity.onFeedback") && ...
    strcmpi(char(string(grantObserved.InterferenceMode(1))), char(string(row.InterferenceMode(1)))), ...
    "Executed PUCCH grant rows must preserve truthful execution/interference/runtime-consumer evidence.");

ok = true;
end

function row = localEmptyFeedbackRow()
row = struct( ...
    "Direction", "", "UEIndex", NaN, "RNTI", NaN, ...
    "HarqID", NaN, "SourceSlot", NaN, "DueSlot", NaN, "Ack", false, ...
    "CurrentDecodeOK", false, "CombinedDecodeOK", false, ...
    "ServingCell", NaN, "BaseStationID", NaN, "TBSBits", NaN, "UCIBitCount", NaN, ...
    "RequestedFormat", NaN, "ResolvedFormat", NaN, "PUCCHResourceId", "", ...
    "PUCCHPRBStart", NaN, "PUCCHPRBCount", NaN, ...
    "PUCCHSymbolStart", NaN, "PUCCHNumSymbols", NaN, ...
    "UCIType", "", "ControlResourceSource", "", "PUCCHGrantId", "", "Processed", false);
end

function outcome = ternaryDetectionOutcome(contentMatch)
if contentMatch
    outcome = "detected";
else
    outcome = "missed";
end
end
