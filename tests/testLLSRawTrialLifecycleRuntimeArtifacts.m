function ok = testLLSRawTrialLifecycleRuntimeArtifacts()
%TESTLLSRAWTRIALLIFECYCLERUNTIMEARTIFACTS Verify raw DL/UL CSVs finalize primary truth rows.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

baseScenario = fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml");
scenarioPath = fullfile(tmp, "__lls_raw_trial_lifecycle_focus.yaml");
fid = fopen(scenarioPath, "w");
assert(fid >= 0, "Unable to create focused lifecycle scenario file.");
fprintf(fid, "%s", ['{' ...
    '"inherits":["' strrep(baseScenario, '\', '\\') '"],' ...
    '"meta":{"scenario_id":"lls_raw_trial_lifecycle_runtime_artifacts","description":"focused raw-trial lifecycle export test","version":"1","owner":"test","maturity_tag":"experimental"},' ...
    '"simulation":{"n_frames":1,"n_slots":2,"n_subframes":1,"monte_carlo_iterations":1,"random_seed":73042,"snr_db":8,"snr_sweep_offsets_db":[0],"noise_operating_mode":"receiver_noise_figure_thermal_noise"},' ...
    '"run_control":{"execution_mode":"LLS","num_workers":1,"total_slots":2,"warmup_slots":0,"measurement_slots":2,"total_time_ms":2,"warmup_time_ms":0,"measurement_time_ms":2},' ...
    '"deployment_topology":{"inter_site_distance":640,"num_cells":1,"num_ues":1,"num_trps":1},' ...
    '"mobility":{"ue_speed_kmh":42,"trajectory_model":"zigzag","update_period_s":0.001},' ...
    '"mimo":{"n_tx_ant":2,"n_rx_ant":2},' ...
    '"antenna_and_array":{"bs_num_antenna_elements":2,"ue_num_antenna_elements":2,"element_spacing_h":0.75,"element_spacing_v":0.5,"polarization":"single"},' ...
    '"channels":{"doppler_source_mode":"derive_from_ue_speed","mobility_kmph":42},' ...
    '"interference":{"inter_cell_execution_mode":"none","inter_cell_interference_enable":false,"inter_cell_interference_flag":false},' ...
    '"control_gating":{"pbch_required":false,"prach_required":false,"pdcch_required":false,"srs_required":false,"trs_required":false,"trs_max_age_slots":4},' ...
    '"users":{"enabled":true,"n_users":1,"execution_model":"slot_coupled_truth","beam_selection_strategy":"fixed_first_beam","save_user_tables":true},' ...
    '"output":{"backend":"filesystem","profile":"lls_raw_trial_lifecycle_runtime_artifacts","save_figures":false,"save_png":false,"save_mat":false}}']);
fclose(fid);

out = run_6g_phy_lls_single(scenarioPath, tmp, "lifecycle_v7");
assert(logical(sixgr.util.structGet(out.Result, "RunCompleted", false)), ...
    ["Focused lifecycle execution must reach completed or " ...
    "completed-with-failures finalization. Publication qualification is " ...
    "outside this two-slot test's claim and remains independently gated."]);

runFolder = char(string(out.RunFolder));
dlFile = fullfile(runFolder, "air_interface", "csv", "dl_pdsch_trials.csv");
ulFile = fullfile(runFolder, "air_interface", "csv", "ul_pusch_trials.csv");
assert(exist(dlFile, "file") == 2 && exist(ulFile, "file") == 2, ...
    "Focused lifecycle run must emit canonical raw DL/UL trial CSVs.");

dlT = readtable(dlFile, "VariableNamingRule", "preserve");
ulT = readtable(ulFile, "VariableNamingRule", "preserve");
localAssertExportedLifecycle(dlT, "DL");
localAssertExportedLifecycle(ulT, "UL");

harqFile = fullfile(runFolder, "harq", "csv", "live_harq_observation_timeline.csv");
assert(exist(harqFile, "file") == 2, ...
    "Focused lifecycle run must emit its canonical HARQ timeline.");
harqT = readtable(harqFile, "VariableNamingRule", "preserve", "TextType", "string");
assert(~isempty(harqT) && ismember("TBId", string(harqT.Properties.VariableNames)) && ...
    all(strlength(strtrim(string(harqT.TBId))) > 0), ...
    "Every executed runtime HARQ attempt must carry its immutable transport-block identity.");

ok = true;
end

function localAssertExportedLifecycle(T, direction)
assert(istable(T) && ~isempty(T), ...
    "Expected nonempty raw %s trial CSV.", direction);
requiredVars = { ...
    'BitsCompared','Goodput_Mbps','MCSIndex','Modulation','TargetCodeRate', ...
    'PrimaryTruthValueStatus','SecondaryFieldGapFlag','SecondaryFieldGapCount','SecondaryFieldGapReason', ...
    'LargeScaleSINRValueStatus','RowLifecycleState','PartialRowFlag','FinalizedFlag','NAReason', ...
    'RuntimeMaterializationStatus','RuntimeEvidenceSource'};
assert(all(ismember(requiredVars, T.Properties.VariableNames)), ...
    "Exported raw %s trial CSV must expose lifecycle truth columns.", direction);

coreTruthMask = isfinite(double(T.BitsCompared)) & isfinite(double(T.Goodput_Mbps)) & ...
    isfinite(double(T.MCSIndex)) & isfinite(double(T.TargetCodeRate)) & ...
    strlength(strtrim(string(T.Modulation))) > 0 & ~logical(T.Crash);
assert(any(coreTruthMask), ...
    "Exported raw %s trial CSV must contain at least one core-truth row.", direction);
assert(all(logical(T.FinalizedFlag(coreTruthMask))), ...
    "Exported raw %s rows with core decode/grant truth must finalize instead of staying partial.", direction);
assert(all(strcmpi(string(T.RowLifecycleState(coreTruthMask)), "finalized")) && ...
    all(~logical(T.PartialRowFlag(coreTruthMask))) && ...
    all(strcmpi(string(T.PrimaryTruthValueStatus(coreTruthMask)), "OK")), ...
    "Exported raw %s core-truth rows must use finalized primary-truth lifecycle semantics.", direction);
assert(all(strlength(strtrim(string(T.RuntimeMaterializationStatus(coreTruthMask)))) > 0) && ...
    all(strlength(strtrim(string(T.RuntimeEvidenceSource(coreTruthMask)))) > 0), ...
    "Exported raw %s core-truth rows must disclose the active runtime materialization/evidence path.", direction);
naReason = string(T.NAReason(coreTruthMask));
assert(all(ismissing(naReason) | strlength(naReason) == 0), ...
    "Exported raw %s finalized core-truth rows must not carry row-level NA reasons.", direction);

gapMask = coreTruthMask & logical(T.SecondaryFieldGapFlag);
if any(gapMask)
    assert(all(logical(T.FinalizedFlag(gapMask))), ...
        "Exported raw %s secondary-gap rows must remain finalized when their primary truth is complete.", direction);
    assert(any(contains(string(T.SecondaryFieldGapReason(gapMask)), "large_scale_sinr_not_finalized")), ...
        "Exported raw %s trial CSV must disclose unresolved preview SINR as a secondary gap when present.", direction);
    assert(any(strcmpi(string(T.LargeScaleSINRValueStatus(gapMask)), "NOT_AVAILABLE")), ...
        "Exported raw %s finalized rows must preserve field-level NOT_AVAILABLE lineage for preview SINR gaps when present.", direction);
end
end
