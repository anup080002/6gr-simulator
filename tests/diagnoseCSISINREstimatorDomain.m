function [summary,folder]=diagnoseCSISINREstimatorDomain(episodes)
% Independent received-grid estimator investigation, NOT scenario evidence.
% Keep the failed single-realization acceptance test unchanged. Compare
% paired channel/noise realizations to distinguish deterministic estimator
% self-noise, noise scaling and finite-population variation before a repair.
% Injected noise is audit-only; it never enters the production estimator.
if nargin<1, episodes=64; end
validateattributes(episodes,{'numeric'},{'scalar','integer','>=',2});
setup6GRSimToolkit('Verbose',false);
previousRNG=rng; cleanup=onCleanup(@()rng(previousRNG));
folder=fullfile(pwd,'results','diagnostics','csi_sinr_estimator_domain', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
assert(~isfolder(folder),'test:EvidenceExists','Preserve previous measurements.');
mkdir(folder);
carrier=nrCarrierConfig('NSizeGrid',100,'SubcarrierSpacing',30);
csirs=nrCSIRSConfig('CSIRSType','nzp','CSIRSPeriod','on','RowNumber',3, ...
    'Density','one','SymbolLocations',4,'SubcarrierLocations',0,'NumRB',100);
reference=nrResourceGrid(carrier,2);
reference(nrCSIRSIndices(carrier,csirs))=nrCSIRS(carrier,csirs);
indices=double(nrCSIRSIndices(carrier,csirs));
port0=indices(indices<=1200*14);
profiles=[ones(1200,1),exp(-2i*pi*(0:1199)'/600)];
names=["flat_port3000_only","phase_selective_port3000_only"];
variance=10^(-12/10);
rows=table();
for episode=1:episodes
    seed=2401400+episode;
    stream=RandStream('mt19937ar','Seed',seed);
    noise=sqrt(variance/2)*complex(randn(stream,1200,14),randn(stream,1200,14));
    noiseOnly=sixgr.phy.refsig.measureCSISINRFromResourceGrid(carrier,csirs,noise);
    for profile=1:numel(names)
        clean=reference(:,:,1).*profiles(:,profile);
        measured=sixgr.phy.refsig.measureCSISINRFromResourceGrid(carrier,csirs,clean+noise);
        noiseless=sixgr.phy.refsig.measureCSISINRFromResourceGrid(carrier,csirs,clean);
        actualPower=mean(abs(clean(port0)).^2);
        row=table(episode,seed,names(profile),variance, ...
            mean(abs(noise(port0)).^2),actualPower, ...
            measured.DesiredPowerPerReceiveAntenna, ...
            measured.NoiseInterferencePowerPerReceiveAntenna, ...
            noiseOnly.NoiseInterferencePowerPerReceiveAntenna, ...
            noiseless.NoiseInterferencePowerPerReceiveAntenna, ...
            measured.CSI_SINR_dB,10*log10(actualPower/variance), ...
            abs(measured.CSI_SINR_dB-12)<1.5,false, ...
            'VariableNames',{'Episode','Seed','Profile','InjectedNoiseVarianceAuditOnly', ...
            'RealizedNoisePowerOnReferenceREsAuditOnly','ExecutedReferencePowerAuditOnly', ...
            'MeasuredReferencePower','MeasuredDisturbance','NoiseOnlyMeasuredDisturbance', ...
            'NoiselessMeasuredDisturbance','MeasuredCSI_SINR_dB','PopulationReferenceSNR_dB', ...
            'WithinOriginalSingleEpisodeGate','ScenarioAccepted'});
        rows=[rows;row]; %#ok<AGROW>
    end
end
summary=table();
for name=names
    selected=rows(rows.Profile==name,:);
    ratio=selected.MeasuredDisturbance/variance;
    pairedExcess=(selected.MeasuredDisturbance-selected.NoiseOnlyMeasuredDisturbance)/variance;
    row=table(name,height(selected),mean(ratio),std(ratio)/sqrt(height(selected)), ...
        mean(selected.NoiseOnlyMeasuredDisturbance)/variance, ...
        mean(selected.NoiselessMeasuredDisturbance)/variance, ...
        mean(pairedExcess),std(pairedExcess)/sqrt(height(selected)), ...
        mean(selected.MeasuredCSI_SINR_dB),sum(selected.WithinOriginalSingleEpisodeGate),false, ...
        'VariableNames',{'Profile','IndependentEpisodes','MeanDisturbanceToInjectedRatio', ...
        'DisturbanceRatioStandardError','MeanNoiseOnlyToInjectedRatio', ...
        'NoiselessDisturbanceToInjectedRatio','PairedExcessDisturbanceToInjectedRatio', ...
        'PairedExcessRatioStandardError','MeanMeasuredCSI_SINR_dB', ...
        'EpisodesWithinOriginalGate','StatisticallyQualified'});
    summary=[summary;row]; %#ok<AGROW>
end
% Record the software estimator identity for version-dependent comparisons.
estimator=which('nrChannelEstimate');
[status,revision]=system('git rev-parse HEAD'); assert(status==0);
scope=struct('Scope',"independent_grid_estimator_RCA_not_waveform_or_scenario_acceptance", ...
    'MATLABVersion',version,'GitCommit',strtrim(revision), ...
    'EstimatorFile',estimator,'EstimatorSHA256',sixgr.phy.waveform.WaveformHash.file(estimator), ...
    'InjectedNoiseUsedByEstimator',false,'SourceAcceptanceAssertionChanged',false, ...
    'ScenarioAccepted',false,'StatisticallyQualified',false,'IndependentEpisodesPerProfile',episodes);
sixgr.util.csvWriteTable(fullfile(folder,'paired_estimator_measurements.csv'),rows, ...
    'PreserveSchema',true,'RoundTripNumericText',true);
sixgr.util.csvWriteTable(fullfile(folder,'estimator_population_summary.csv'),summary, ...
    'PreserveSchema',true,'RoundTripNumericText',true);
save(fullfile(folder,'estimator_domain.mat'),'rows','summary','scope','carrier','csirs','-v7.3');
sixgr.util.jsonWrite(fullfile(folder,'scope.json'),scope);
disp(summary);
fprintf('CSI_ESTIMATOR_DOMAIN_RCA=%s scenario_accepted=0 assertion_unchanged=1\n',folder);
end
