function ok = testSequentialIntervalAuthority()
%TESTSEQUENTIALINTERVALAUTHORITY Interval policy must be explicit and auditable.

setup6GRSimToolkit("Verbose", false);

base = struct( ...
    "MinTrials", 20, ...
    "MinErrors", 2, ...
    "MaxTrials", 100, ...
    "MaxLooks", 5, ...
    "LookSchedule", 20:20:100, ...
    "TargetHalfWidth", 0.20, ...
    "TargetZeroErrorUpperBound", 0.20, ...
    "NominalConfidenceLevel", 0.95);

cpProfile = base;
cpProfile.IntervalMethod = "CLOPPER_PEARSON_TWO_SIDED";
cpDesign = sixgr.validation.SequentialDesign.fromProfile(cpProfile);
cpDecision = sixgr.validation.SequentialStoppingPolicy.evaluate( ...
    5, 40, cpDesign, 2);
assert(string(cpDesign.IntervalMethod) == ...
    "CLOPPER_PEARSON_TWO_SIDED" && ...
    string(cpDecision.Method) == "CLOPPER_PEARSON_TWO_SIDED", ...
    "Clopper-Pearson policy must reach the nonzero-error sequential interval.");

wilsonProfile = base;
wilsonProfile.IntervalMethod = "WILSON_TWO_SIDED";
wilsonDesign = sixgr.validation.SequentialDesign.fromProfile(wilsonProfile);
wilsonDecision = sixgr.validation.SequentialStoppingPolicy.evaluate( ...
    5, 40, wilsonDesign, 2);
assert(string(wilsonDesign.IntervalMethod) == "WILSON_TWO_SIDED" && ...
    string(wilsonDecision.Method) == "WILSON_TWO_SIDED", ...
    "Wilson policy must reach the nonzero-error sequential interval.");
assert(abs(double(cpDecision.Lower) - double(wilsonDecision.Lower)) > eps || ...
    abs(double(cpDecision.Upper) - double(wilsonDecision.Upper)) > eps, ...
    "Distinct configured interval methods must not collapse to one hard-coded result.");

zeroDecision = sixgr.validation.SequentialStoppingPolicy.evaluate( ...
    0, 40, wilsonDesign, 2);
assert(string(zeroDecision.Method) == ...
    "CLOPPER_PEARSON_ONE_SIDED_UPPER" && ...
    string(zeroDecision.Sidedness) == "ONE_SIDED_UPPER", ...
    "Zero-error censoring must use the exact one-sided upper bound.");
expectedUpper = 1 - (1 - double(wilsonDesign.LookConfidenceLevel))^(1 / 40);
assert(abs(double(zeroDecision.Upper) - expectedUpper) < 1e-12, ...
    "Zero-error upper bound does not match the exact binomial result.");

badProfile = base;
badProfile.IntervalMethod = "HIDDEN_DEFAULT";
localAssertError(@() sixgr.validation.SequentialDesign.fromProfile(badProfile), ...
    "sixgr:validation:InvalidSequentialIntervalMethod");

fprintf("Sequential interval authority: CP/Wilson/zero-error exact paths verified.\n");
ok = true;
end

function localAssertError(f, expectedID)
caught = false;
try
    f();
catch ME
    caught = true;
    assert(string(ME.identifier) == string(expectedID), ...
        "Expected %s, received %s.", expectedID, ME.identifier);
end
assert(caught, "Expected error %s was not thrown.", expectedID);
end
