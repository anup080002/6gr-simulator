function ok = testFourStepRARuntimeStageComposer()
%TESTFOURSTEPRARUNTIMESTAGECOMPOSER Coupled RA composes strict runtime waveforms.
cfg = raStrictAnchorConfig();
% Explicit association fixture, not a claim that this unit decoded SSB.
% Exercise the real Msg2/Msg4 projection/export path on a nonzero SSB ID.
cfg.phy.ssb.Lmax = 8;
cfg.phy.ssb.activeBitmap = "00010000";
cfg.phy.ssb.runtimeSSBIndex = 3;
cfg.phy.ssb.precoderMatrices = 1;
cfg.phy.ssb.precoderIDs = "component_associated_ssb_mapping";
cfg.random_access.common_downlink_beam_source = "selected_ssb_beam";
cfg.random_access.associated_ssb_index = 3;
cfg.random_access.associated_ssb_selection_source = "component_fixture_not_measured_selection";
% Keep nonzero SSB identity. SearchSpaceZero=0 maps i_SSB=3 to
% slot 43, which is UL in this anchor; never move it silently in production.
carrier=sixgr.phy.grid.makeCarrier(cfg);
rejected=false;
try
    sixgr.phy.broadcast.resolveSIB1ControlOccasion(carrier,cfg);
catch err
    assert(strcmp(err.identifier,'sixgr:phy:broadcast:Type0OccasionNotDLCapable'));
    rejected=true;
end
assert(rejected,'The original UL Type-0 occasion must remain rejected.');
% TS 38.213 Tables 13-4/13-11: CORESET index 5 is 24 RB/3 symbols;
% SearchSpaceZero=1 uses O=0,M=1/2. For odd i_SSB=3 control occupies
% symbols 3:5 in DL slot 41, clear of the SIB1 DM-RS at symbol 2.
% SIB1 data is rate-matched around the actual PDCCH by RASIPDSCHContext.
cfg.phy.mib.pdcchConfigSIB1=16*5+1;
cfg.phy.sib1.coreset0Index=5;
cfg.phy.sib1.searchSpaceZero=1;
[siControl,siCfg,siCarrier,~,siSlot]= ...
    sixgr.phy.broadcast.resolveSIB1ControlOccasion(carrier,cfg);
assert(siSlot==41 && siControl.SearchSpace.StartSymbolWithinSlot==3 && ...
    siControl.CORESET.Duration==3);
siData=sixgr.phy.broadcast.configuredSIB1Allocation(siCarrier,siCfg);
[controlRE,~,controlDMRS]=nrPDCCHResources(siCarrier,siControl);
assert(isempty(intersect(double(nrPDSCHDMRSIndices(siCarrier,siData)), ...
    double([controlRE(:);controlDMRS(:)]))), ...
    'SIB1 DM-RS cannot collide with Type-0 control REs.');
res = sixgr.truth.CoupledTruthRuntime.runFourStepRARuntime(cfg, ...
    "RunId", "test_ra_runtime_stage_composer", ...
    "UEId", 1, "CellId", 1, "AttemptId", 1, ...
    "RuntimeSlot", 1, ...
    "RequireRuntimeStageWaveforms", true, ...
    "WriteArtifacts", false);

assert(logical(res.RACompleted) && logical(res.StrictOk), ...
    "Coupled runtime RA must complete Msg1-Msg4 when composing strict stage waveforms.");
assert(logical(res.RuntimeStageWaveformsRequired), ...
    "The result must disclose that strict runtime stage waveforms were required.");
assert(logical(res.RuntimeStageWaveformsUsed), ...
    "The coupled composer must mark the propagated stage waveforms as consumed.");
assert(logical(res.RuntimeChannelStateUsed), ...
    "Composed RA stage waveforms must traverse the runtime channel-state transport.");
assert(~logical(res.RuntimeSelfLoopWaveformsUsed), ...
    "Strict coupled RA stage composition must not fall back to self-loop waveforms.");
assert(string(res.RuntimeTransportMode) == "coupled_runtime_stage_waveform_composer", ...
    "Runtime transport mode must disclose coupled stage-waveform composition.");

T = res.ArtifactTables.ra_runtime_stage_waveforms;
native=res.ObservedREAllocationTable;
assert(~isempty(native) && all(native.grid_domain=="prach_native_ofdm") && ...
    all(native.waveform_hash_plane=="prach_after_preamble_power_control_before_spatial_mapping_and_rf") && ...
    all(native.waveform_sha256==string(sixgr.phy.waveform.WaveformHash.numeric(res.Msg1Tx.Waveform))), ...
    'Msg1 export must hash and label the actual power-controlled waveform, not a pre-power generator copy.');
expectedStages = ["Msg1","Msg2","Msg3","Msg4","RRCSetupComplete"];
assert(height(T) == numel(expectedStages), ...
    "Strict runtime RA must publish one composed transport row per waveform-carried message.");
assert(isequal(string(T.StageName).', expectedStages), ...
    "Strict runtime RA stages must include ordered Msg1-Msg4 and RRCSetupComplete.");
assert(all(logical(T.RuntimeStageWaveformUsed)), ...
    "Every RA stage must consume a composed propagated waveform.");
assert(all(logical(T.RuntimeChannelStateUsed)), ...
    "Every composed RA stage must be backed by runtime channel state.");
assert(~any(logical(T.SelfLoopWaveformUsed)), ...
    "No composed RA stage may use direct TX self-loop samples.");
assert(all(T.ObservationStartSample==T.RuntimeChannelStartSample) && ...
    all(T.ObservationEndSampleExclusive==T.RuntimeChannelEndSample) && ...
    all(T.ObservationEndSampleExclusive-T.ObservationStartSample==T.RxSampleCount) && ...
    all(isfinite(T.ObservationSampleRateHz) & T.ObservationSampleRateHz>0) && ...
    all(T.ObservationCompletionTime_s==T.ObservationEndSampleExclusive./T.ObservationSampleRateHz) && ...
    all(T.ObservationCoverageSource=="executed_runtime_channel_sample_extent"), ...
    'Connected consumers need the actual composed receiver clock, not an inferred slot end.');
assert(all(string(T.WaveformSource) == "coupled_runtime_stage_waveform_composer"), ...
    "Strict composed RA stages must identify their waveform source.");
assert(any(contains(string(T.RuntimeChannelLinkKey), "dir=UL")) && ...
    any(contains(string(T.RuntimeChannelLinkKey), "dir=DL")), ...
    "Strict composed RA must use both UL and DL persistent link keys.");
for k=1:height(T)
    if any(string(T.StageName(k))==["Msg2","Msg4"])
        evidence=jsondecode(T.TxSSBAssociationJSON(k));
        assert(evidence.SourceReferenceSignalId==3 && string(evidence.SourceReferenceSignal)=="SSB");
        assert(string(T.TxBeamId(k))=="component_associated_ssb_mapping");
        assert(string(evidence.ProjectionMatrixSHA256)== ...
            string(sixgr.phy.mimo.MatrixContract.digest(1)));
        assert(string(evidence.SelectionSource)=="component_fixture_not_measured_selection");
        assert(contains(string(evidence.Scope),"not_receiver_QCL_or_TCI_activation"));
    else
        assert(strlength(string(T.TxSSBAssociationJSON(k)))==0, ...
            'UL stages must not inherit a DL SSB projection claim.');
    end
end
ok = true;
end
