function ok=testSRSScoringReferenceIndependence()
% Declared mathematical receiver fixture, not a waveform qualification.
% Scoring-reference poisoning must never change receiver noise or RI/TPMI.
setup6GRSimToolkit('Verbose',false);
n=72; k=(0:n-1).';
stream=RandStream('mt19937ar','Seed',249312);
reference=exp(1i*pi/2*mod(k,4));
received=reference.*(0.7+0.2i)+sqrt(0.04/2)* ...
    complex(randn(stream,n,1),randn(stream,n,1));
coordinates=table(zeros(n,1),zeros(n,1),k,floor(k/12),zeros(n,1), ...
    'VariableNames',{'Slot','Symbol','Subcarrier','PRB','Port'});
det=struct('DetectionSuccess',true,'Coverage', ...
    struct('PRBStart',0,'OccupiedPRBCount',6),'Extracted', ...
    struct('ObservedSymbols',received,'ReferenceSymbols',reference, ...
    'Table',coordinates,'AppliedChannelGains',repmat(0.7+0.2i,n,1)));
cfg=struct('RunId',"declared_scoring_independence_fixture", ...
    'ResourceId',1,'UEId',1,'NumSRSPorts',1,'CombNumber',2, ...
    'CombOffset',0,'CyclicShift',0,'SequenceId',0, ...
    'ChannelNMSEThresholddB',-8,'ConfigHash',"declared_math_fixture", ...
    'ChannelEstimatorAlgorithm',"mmse_wiener", ...
    'ChannelEstimatorInterpolation',"linear", ...
    'MMSEFrequencySmoothingBins',9,'DFTDelayTapKeepCount',1, ...
    'RequireTrueChannelOracleForValidation',false,'BaseConfig',struct());
normal=sixgr.phy.srs.estimateULChannelFromSRS(det,cfg);
poisoned=det;
poisoned.Extracted.AppliedChannelGains=100*exp(1i*k);
changed=sixgr.phy.srs.estimateULChannelFromSRS(poisoned,cfg);
missing=det; missing.Extracted=rmfield(missing.Extracted,'AppliedChannelGains');
absent=sixgr.phy.srs.estimateULChannelFromSRS(missing,cfg);
fprintf('SRS_SCORING_POISON_REPLAY noise_normal=%.16g noise_poisoned=%.16g noise_absent=%.16g\n', ...
    normal.NoiseVarianceEstimate,changed.NoiseVarianceEstimate,absent.NoiseVarianceEstimate);
assert(isequaln(normal.HestPerRE,changed.HestPerRE) && ...
    isequaln(normal.HestPerRE,absent.HestPerRE));
assert(isequaln(normal.NoiseVarianceEstimate,changed.NoiseVarianceEstimate) && ...
    isequaln(normal.NoiseVarianceEstimate,absent.NoiseVarianceEstimate), ...
    'test:SRSScoringReferenceLeak', ...
    'Changing only independent scoring truth changed practical receiver noise.');
assert(isequaln(normal.SRSRITPMI,changed.SRSRITPMI) && ...
    isequaln(normal.SRSRITPMI,absent.SRSRITPMI), ...
    'test:SRSScoringReferenceLeak','Scoring truth changed RI/TPMI selection evidence.');
assert(~isequaln(normal.TrueChannelNMSE_dB,changed.TrueChannelNMSE_dB) && ...
    isnan(absent.TrueChannelNMSE_dB), ...
    'Scoring must still expose wrong or unavailable independent references.');
assert(normal.NoiseVarianceSource=="received_ls_minus_practical_estimator_residual" && ...
    normal.NoiseVarianceStatus=="pilot_fit_residual_not_independently_qualified_noise");
% Plain LS has identically zero in-sample fit residual. Do not replace that
% missing independent noise observation with eps and infer near-infinite MI.
lsCfg=cfg; lsCfg.ChannelEstimatorAlgorithm="ls";
unidentified=sixgr.phy.srs.estimateULChannelFromSRS(det,lsCfg);
assert(isnan(unidentified.NoiseVarianceEstimate) && ...
    ~unidentified.SRSRITPMI.Valid && isnan(unidentified.RIEstimate) && ...
    unidentified.RISource=="srs_receiver_noise_unavailable");
fprintf('SRS_SCORING_REFERENCE_INDEPENDENCE_PASS declared_math_fixture=1\n');
ok=true;
end
