function ok=testH4100CombinedUCIBudget()
% H4 resource capacity, typed coding and bounded AWGN PUCCH waveforms.
% This is not array/RF, statistical UCI, or full-scenario qualification.
% Receiver hypotheses are constructed before TX reports and contain no bits.
setup6GRSimToolkit('Verbose',false);
source=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_gate.yaml');
cfg=sixgr.lls6g.buildInternalConfig(source,tempname);
folder=fullfile(pwd,'results','lls','h4_combined_uci', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(folder);
scope="declared_H4_UCI_obligation_actual_AWGN_waveform_not_full_scenario";
save(fullfile(folder,'configuration.mat'),'cfg','scope');
ue=struct('UEID',1,'RNTI',cfg.phy.pdsch.RNTI,'ServingCell',1, ...
    'PUCCHCell',1,'ComponentCarrier',cfg.phy.frame.DefaultIdentity.ScheduledCCID, ...
    'ActiveULBWP',cfg.phy.frame.DefaultIdentity.ULBWPID);
rrc=sixgr.phy.pucch.PUCCHConfigBuilder.receiverConfiguration(cfg,ue);
installed=sixgr.phy.mimo.CSIReportConfiguration( ...
    cfg.phy.csi.reportConfiguration,cfg.phy.csi.reportConfiguration.Epoch);
assert(installed.part1BitCount()==14 && installed.part2BitCount()==0);
assert(rrc.maxCodeRate(2)==0.35,'Do not relax the configured UCI rate gate.');
frame=struct('K1',1,'K1Source','declared_component_received_DCI', ...
    'PDSCHEndSlot',18,'TargetSlot',19,'DecodedPRI',0,'PRIFieldWidth',3, ...
    'PRIProvenance','declared_component_received_DCI','FirstCCE',0, ...
    'NumCCE',16,'SlotSymbolOwnership',"DDDDDDDDDDGGUU", ...
    'FlexibleResolutionProvided',false);
initial=sixgr.truth.initializeConfiguredSRProcedures(cfg,ue);
frame.SchedulingRequestStates= ...
    sixgr.phy.pucch.SchedulingRequestState.atSlot(initial,18);

% Preserve the original counterexample: a configured two-PRB maximum cannot
% carry two HARQ bits plus SR plus the full eight-resource H4 CSI report.
legacy=rrc.resourceByID(10).Data; legacy.NumPRBs=2;
carrier=sixgr.phy.grid.makeCarrier(cfg);
[selected,oldBudget]=sixgr.phy.pucch.PUCCHResource(legacy).selectPRBAllocation( ...
    carrier,2+1+installed.part1BitCount(),rrc.maxCodeRate(2),"dynamic_harq_csi");
assert(isempty(selected) && oldBudget.RequiresCSISelection && ...
    oldBudget.CapacityBits==64 && oldBudget.AllocationInputBits==23 && ...
    ~oldBudget.RateConstraintSatisfied);
fprintf('H4_OLD_UCI_CAPACITY_REPRODUCED A=%d CRC=%d E=%d rate=%g limit=%g\n', ...
    oldBudget.InformationBits,oldBudget.TotalCRCBits,oldBudget.CapacityBits, ...
    oldBudget.InformationAndCRCRate,oldBudget.MaxCodeRate);

% Explicit capacity envelope, not fabricated received DCI events: test up to
% eight HARQ bits (the configured K1 horizon), including CRC-size transition.
% This does not claim every population occurs in the D,D,D,S,U schedule.
count=0; waveformCount=0;
for rank=cfg.phy.csi.reportConfiguration.AllowedRanks
    request=cfg.phy.csi.reportConfiguration; request.Rank=rank;
    txSchema=sixgr.phy.mimo.CSIReportConfiguration(request,request.Epoch);
    for nHARQ=[0 1 2 3 4 8]
        obligation=struct('ObservationID',"H4-UCI-budget-"+rank+"-"+nHARQ, ...
            'ConfigurationEpoch',rrc.ConfigurationEpoch,'HARQBitCount',nHARQ, ...
            'SRBitCount',1,'PriorityIndex',0, ...
            'CSIReportConfigID',installed.ReportConfigID, ...
            'CSIConfigurationEpoch',installed.Epoch);
        context=sixgr.truth.buildConfiguredPUCCHReceiveContext(obligation,installed);
        procedure="dynamic_harq_csi";
        if nHARQ==0, procedure="configured_csi"; end
        identity=struct('ObservationID',obligation.ObservationID,'ResourceID',10, ...
            'RNTI',ue.RNTI,'AbsoluteSlot0',18, ...
            'Source',"installed_H4_component_obligation", ...
            'TimingSource',"configured_special_slot", ...
            'ResourceSelectionProcedure',procedure);
        rx=sixgr.phy.pucch.PUCCHReceptionAssignment(identity,rrc,context);
        frozen=context.Digest;

        [~,values]=sixgr.phy.mimo.TypeISinglePanelCodebook.matrix(request,0);
        values.RI=rank; values.CRI=7; values.CQI_CW0=11;
        csi=txSchema.build(values);
        harq=int8(mod((1:nHARQ).',2));
        if nHARQ==0
            tx=sixgr.phy.pucch.PUCCHConfigBuilder.planCSI( ...
                cfg,ue,csi.Part1Bits,csi.Part2Bits,frame);
        else
            tx=sixgr.phy.pucch.PUCCHConfigBuilder.planCombined( ...
                cfg,ue,harq,csi.Part1Bits,csi.Part2Bits,frame);
        end
        assert(isempty(tx.Plan.Data.CSISelection.OmittedReportIDs) && ...
            tx.ReceiverContext.CSIPart1Bits==14 && tx.ReceiverContext.SRBits==1 && ...
            tx.ReceiverContext.HARQACKBits==nHARQ && context.Digest==frozen);
        assert(rx.Resource.Digest==tx.Plan.Resource.Digest && ...
            rx.Data.AllocationBudget.RateConstraintSatisfied && ...
            tx.Plan.Data.AllocationBudget.RateConstraintSatisfied);
        serialized=sixgr.phy.pucch.UCIReportSerializer.serialize(tx.Report);
        [~,native]=nrPUCCHIndices(carrier,rx.Resource.toolboxConfig());
        coded=sixgr.phy.pucch.UCIEncoder.encode(serialized.Sequence1,native.G);
        decoded=sixgr.phy.pucch.UCIDecoder.decode( ...
            20*(1-2*double(coded.CodedBits)),context.Sequence1Length);
        assert(decoded.CRCApplicable && decoded.CRCPassed && ...
            isequal(decoded.Bits,serialized.Sequence1.Bits));
        received=installed.decode(decoded.Bits(nHARQ+2:end),int8([]));
        assert(received.RI==rank && received.CRI==7 && ...
            received.PMI==0 && received.CQI_CW0==11);
        nativeResource=rx.Resource.toolboxConfig();
        assert(all(nativeResource.PRBSet>=0) && ...
            max(nativeResource.PRBSet)<273 && ...
            isequal(nativeResource.SymbolAllocation,[12 2]));
        if ismember(nHARQ,[0 2 8])
            localWaveform(carrier,tx,rx,context,serialized,rank,nHARQ,folder);
            waveformCount=waveformCount+1;
        end
        count=count+1;
    end
end
fprintf(['H4_COMBINED_UCI_BUDGET_PASS cases=%d AWGN_waveforms=%d ' ...
    'RF_qualified=0 whole_CSI_retained=1 folder=%s\n'],count,waveformCount,folder);
ok=true;
end

function localWaveform(carrier,planned,assignment,context,serialized,rank,nHARQ,folder)
% The only declared boundary is the UCI obligation. The receiver obtains
% noise/channel estimates from its captured DMRS, not TX bits or metadata.
carrier.NSlot=mod(assignment.Data.AbsoluteSlot0,carrier.SlotsPerFrame);
carrier.NFrame=floor(assignment.Data.AbsoluteSlot0/carrier.SlotsPerFrame);
fixture=sixgr.phy.pucch.PUCCHFixtureFactory.connected(2,int8([1;0;1]));
power=struct('Mu',log2(carrier.SubcarrierSpacing/15), ...
    'MRB',planned.Plan.Resource.Data.NumPRBs,'P0dBm',NaN,'PathlossdB',NaN, ...
    'DeltaFdB',NaN,'DeltaTFdB',NaN,'ClosedLoopAdjustmentdB',NaN,'PCMAXdBm',NaN, ...
    'PathlossReferenceRSID',1,'TPCCommandSource',"not_applicable_normalized_component", ...
    'StateID',"H4-UCI-unit-RE-component", ...
    'OperatingPointAuthority',"configured_occupied_re_esn0", ...
    'ReferenceEnergyPerOccupiedRE',1,'RuntimeMeasuredPathlossUsed',false, ...
    'BandwidthSource',"installed_H4_PUCCH_resource");
txAssignment=sixgr.phy.pucch.PUCCHTransmissionAssignment.fromResourcePlan( ...
    planned.Plan,sixgr.phy.pucch.PUCCHPowerControlState(power), ...
    fixture.UEContext.Data.SpatialRelationState);
tx=sixgr.phy.pucch.PUCCHTransmitter.transmit(carrier,txAssignment,planned.Report);
assert(tx.OFDMInfo.SampleRate==122.88e6 && tx.OFDMInfo.Nfft==4096 && ...
    isnan(tx.Power.AppliedPowerdBm) && tx.Power.NormalizedPowerReference);
[capture,noise]=sixgr.phy.waveform.addOccupiedREAWGN(tx.Waveform,carrier,40, ...
    'SignalEnergyPerOccupiedRE',1,'Seed',100000+rank*100+nHARQ);
rx=sixgr.phy.pucch.PUCCHReceiver.receive(capture,carrier,assignment,context, ...
    'NoiseVariance',NaN,'NoiseVarianceMode','received_dmrs_estimate', ...
    'ChannelProfile','AWGN','DetectionThreshold',0.2);
scope="declared_H4_UCI_obligation_actual_AWGN_waveform_not_array_RF_or_scenario_qualification";
save(fullfile(folder,sprintf('rank%d_harq%d.mat',rank,nHARQ)), ...
    'carrier','context','assignment','tx','capture','noise','rx','scope','-v7.3');
assert(rx.ReceiverOnlyAssignment && ~rx.OraclePayloadBitsUsed && ...
    rx.ReceiverUsable && ~rx.DTX && rx.CRCApplicable && rx.CRCPassed && ...
    isequal([rx.DecodedFields.HARQACK;rx.DecodedFields.SR; ...
    rx.DecodedFields.CSIPart1;rx.DecodedFields.CSIPart2],serialized.Sequence1.Bits));
end
