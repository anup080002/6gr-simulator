function ok = testYAMLImpairmentFeatureAuthority()
%TESTYAMLIMPAIRMENTFEATUREAUTHORITY Prove YAML owns common RF switches.

setup6GRSimToolkit("Verbose", false);
basePath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "master_sinr_sweep.yaml");
base = sixgr.lls6g.config.loadScenarioConfig(basePath).toStruct();
assert(isfield(base.canonical_control, "impairments"), ...
    "The master scenario must expose canonical_control.impairments.");

% Nonzero parameters must not implicitly enable a YAML-disabled feature.
disabled = base;
disabled = localSetImpairments(disabled, false);
disabledPath = string(tempname) + ".json";
disabledCleanup = onCleanup(@()localDelete(disabledPath)); %#ok<NASGU>
sixgr.util.jsonWrite(disabledPath, disabled);
disabledScenario = sixgr.lls6g.config.loadScenarioConfig(disabledPath);
disabledCfg = sixgr.lls6g.buildInternalConfig(disabledScenario, tempdir);

assert(~logical(disabledScenario.get("impairments.cfo_enabled")) && ...
    ~logical(disabledScenario.get("impairments.phase_noise_enabled")) && ...
    ~logical(disabledScenario.get("impairments.iq_imbalance_enabled")) && ...
    ~logical(disabledScenario.get("impairments.timing_offset_enabled")) && ...
    ~logical(disabledScenario.get("impairments.pa_nonlinearity_enabled")), ...
    "Canonical disabled switches must win over inherited legacy aliases.");
assert(~disabledCfg.phy.impairments.cfoEnabled && ...
    disabledCfg.phy.impairments.cfoHz == 0 && ...
    ~disabledCfg.phy.impairments.phaseNoiseEnabled && ...
    ~disabledCfg.phy.impairments.iqImbalanceEnabled && ...
    ~disabledCfg.phy.impairments.timingOffsetEnabled && ...
    disabledCfg.phy.impairments.timingOffsetSamples == 0 && ...
    ~disabledCfg.phy.impairments.paNonlinearityEnabled, ...
    "Disabled YAML switches must disable every PHY impairment consumer.");
assert(~disabledCfg.rf.phaseNoise.enable && ...
    ~disabledCfg.rf.iqImbalance.enable && ...
    ~disabledCfg.rf.pa.enable && ~disabledCfg.rf.enable, ...
    "Disabled YAML switches must disable every RF impairment consumer.");

% The same YAML fields must enable the exact production runtime paths.
enabled = base;
enabled = localSetImpairments(enabled, true);
enabledPath = string(tempname) + ".json";
enabledCleanup = onCleanup(@()localDelete(enabledPath)); %#ok<NASGU>
sixgr.util.jsonWrite(enabledPath, enabled);
enabledScenario = sixgr.lls6g.config.loadScenarioConfig(enabledPath);
enabledCfg = sixgr.lls6g.buildInternalConfig(enabledScenario, tempdir);

assert(logical(enabledScenario.get("impairments.cfo_enabled")) && ...
    logical(enabledScenario.get("impairments.phase_noise_enabled")) && ...
    logical(enabledScenario.get("impairments.iq_imbalance_enabled")) && ...
    logical(enabledScenario.get("impairments.timing_offset_enabled")) && ...
    logical(enabledScenario.get("impairments.pa_nonlinearity_enabled")), ...
    "Canonical enabled switches must win over inherited legacy aliases.");
assert(enabledCfg.phy.impairments.cfoEnabled && ...
    abs(enabledCfg.phy.impairments.cfoHz - 125) < 1e-12 && ...
    enabledCfg.phy.impairments.phaseNoiseEnabled && ...
    enabledCfg.phy.impairments.iqImbalanceEnabled && ...
    enabledCfg.phy.impairments.timingOffsetEnabled && ...
    abs(enabledCfg.phy.impairments.timingOffsetSamples - 2) < 1e-12 && ...
    enabledCfg.phy.impairments.paNonlinearityEnabled, ...
    "Enabled YAML switches and values must reach every PHY consumer.");
assert(enabledCfg.rf.phaseNoise.enable && ...
    enabledCfg.rf.iqImbalance.enable && enabledCfg.rf.pa.enable && ...
    enabledCfg.rf.enable, ...
    "Enabled YAML switches must enable every RF impairment consumer.");

% A post-build MATLAB override must fail at the production waveform edge;
% it must never silently replace the immutable YAML decision.
tampered = enabledCfg;
tampered.phy.impairments.cfoEnabled = false;
localAssertThrows(@()sixgr.link.applyWaveformImpairments( ...
    complex(zeros(16, 1)), tampered, 30.72e6, ...
    "ApplyRFChain", false), ...
    "sixgr:config:YAMLFeatureExecutionMismatch");
ok = true;
end

function cfg = localSetImpairments(cfg, enabled)
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.cfo.enabled", logical(enabled));
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.cfo.value_hz", 125);
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.cfo.model", "fixed");
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.phase_noise.enabled", logical(enabled));
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.phase_noise.model", "lorentzian");
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.iq_imbalance.enabled", logical(enabled));
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.iq_imbalance.model", "widely_linear");
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.iq_imbalance.amplitude_imbalance_db", 3);
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.iq_imbalance.phase_imbalance_deg", 5);
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.to.enabled", logical(enabled));
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.to.value_samples", 2);
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.to.model", "fixed");
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.pa_nonlinearity.enabled", logical(enabled));
cfg = sixgr.util.structSet(cfg, ...
    "canonical_control.impairments.pa_nonlinearity.model", "rapp");
end

function localDelete(path)
if exist(path, "file") == 2
    delete(path);
end
end

function localAssertThrows(fcn, identifier)
didThrow = false;
try
    fcn();
catch ME
    didThrow = strcmp(string(ME.identifier), string(identifier));
    if ~didThrow
        rethrow(ME);
    end
end
assert(didThrow, "Expected typed error %s.", identifier);
end
