function ok = testPDSCHDMRSNoMutation()
%TESTPDSCHDMRSNOMUTATION Prove valid nonconsecutive ports are preserved.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
request = struct( ...
    "MappingType", "A", "DMRSLength", 1, ...
    "PDSCHStartSymbol", 0, "PDSCHDurationLd", 12, ...
    "DMRSTypeAPosition", 2, "DMRSAdditionalPosition", 3, ...
    "DMRSConfigurationType", 1, ...
    "DMRSMultiplexing", "enhanced", ...
    "DMRSPortSet", [0 8], "NumLayers", 2, ...
    "NumCDMGroupsWithoutData", 2, ...
    "NIDNSCID", 411, "NSCID", 1);
before = request;
actual = sixgr.pdsch.PDSCHDMRSValidator. ...
    validateConfiguration(request);
assert(isequaln(request, before) && actual.OriginalUnchanged, ...
    "DM-RS validator mutated the caller configuration.");
assert(isequal(actual.LogicalPortSet, [0 8]) && ...
    isequal([actual.Ports.LogicalPort], [0 8]), ...
    "Nonconsecutive DM-RS ports were replaced or reordered.");
assert(isequal(actual.SymbolPositions, [2 5 8 11]), ...
    "Valid DM-RS symbols were changed during validation.");
ok = true;
end
