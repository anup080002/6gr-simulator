function ok = testLLSResolvedFeatureConfigAuthority()
%TESTLLSRESOLVEDFEATURECONFIGAUTHORITY Keep YAML feature gates in runtime config.

setup6GRSimToolkit("Verbose", false);
scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "lls_4x4_rank2_bidirectional_focused_validation.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>
cfg = sixgr.lls6g.buildInternalConfig(scfg, tmp);

assert(logical(scfg.get("output.artifact_contract_engine.enabled", false)), ...
    "The single resolved output block must enable the runtime artifact contract engine.");
assert(string(scfg.get("output.artifact_contract_engine.catalog_scope", "")) == "runtime_in_path", ...
    "The bounded scenario must use the runtime-in-path artifact catalog.");
assert(string(scfg.get("canonical_control.integration.run_mode", "")) == ...
        "FIXED_SNR_SWEEP", ...
    "Artifact finalization must receive an explicit fixed-SNR run-mode authority.");
assert(string(scfg.get("canonical_control.integration.subprofile", "")) == ...
        "connected_control_smoke", ...
    "The connected scheduler slice must not be normalized as a one-UE calibration grant.");
assert(double(scfg.get("users.n_users", NaN)) == 2 && ...
        double(scfg.get("canonical_control.topology.num_ues", NaN)) == 2, ...
    "Canonical topology must preserve the YAML-requested two-UE runtime.");

assert(~logical(cfg.outputs.emitPlaceholderArtifacts), ...
    "output.emit_placeholder_artifacts=false must reach the internal output policy.");
assert(~logical(cfg.outputs.emitDisabledAuditArtifacts), ...
    "Disabled-only audit artifacts must remain suppressed by the resolved YAML.");
assert(~logical(sixgr.util.structGet(cfg, ...
    "lls6g.output.emit_placeholder_artifacts", true)), ...
    "The resolved output policy must remain available to runtime consumers.");
assert(~logical(sixgr.util.structGet(cfg, ...
    "lls6g.reference_signals.csi_rs_enabled", true)), ...
    "CSI-RS enablement must follow the resolved YAML.");
assert(~logical(sixgr.util.structGet(cfg, ...
    "lls6g.reference_signals.srs_enabled", true)), ...
    "SRS enablement must follow the resolved YAML.");
assert(~logical(sixgr.util.structGet(cfg, ...
    "lls6g.mimo_and_beam_management.beam_sweeping", true)), ...
    "Beam sweeping must follow the resolved YAML.");
assert(~logical(sixgr.util.structGet(cfg, ...
    "lls6g.mimo_and_beam_management.beam_switching", true)), ...
    "Beam switching must follow the resolved YAML.");
assert(~logical(sixgr.util.structGet(cfg, ...
    "lls6g.mimo_and_beam_management.beam_refinement", true)), ...
    "Beam refinement must follow the resolved YAML.");
assert(~logical(sixgr.util.structGet(cfg, "phy.csi.enable", true)), ...
    "CSI reporting must not remain enabled through an inherited alias.");
assert(~logical(sixgr.util.structGet(cfg, "phy.srs.enable", true)), ...
    "SRS execution must follow the resolved YAML.");
assert(logical(sixgr.util.structGet(cfg, "phy.pdcch.enable", false)), ...
    "Scheduler-truth connected DL must explicitly enable PDCCH.");
assert(logical(sixgr.util.structGet(cfg, "phy.pucch.enable", false)), ...
    "Scheduler-truth connected DL must explicitly enable PUCCH feedback.");
assert(logical(sixgr.util.structGet(cfg, "phy.harq.enable", false)), ...
    "Scheduler-truth connected DL must explicitly enable HARQ.");
assert(~logical(sixgr.util.structGet(cfg, "phy.pusch.power_control.enabled", true)), ...
    "UL power control must follow the explicit YAML disable authority.");
assert(~logical(sixgr.util.structGet(cfg, "channel.pathlossEnabled", true)), ...
    "Standalone-AWGN validation must not advertise a pathloss execution path.");
assert(~logical(sixgr.util.structGet(cfg, "channel.shadowFadingEnabled", true)), ...
    "Standalone-AWGN validation must not advertise shadow fading.");
assert(~logical(sixgr.util.structGet(cfg, "rf.enable", true)), ...
    "The bounded clean-RF scenario must not advertise an RF impairment chain.");

ok = true;
fprintf("PASS testLLSResolvedFeatureConfigAuthority: resolved YAML owns runtime feature gates.\n");
end
