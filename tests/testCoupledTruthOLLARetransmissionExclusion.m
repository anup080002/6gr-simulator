function ok = testCoupledTruthOLLARetransmissionExclusion()
%TESTCOUPLEDTRUTHOLLARETRANSMISSIONEXCLUSION Keep HARQ retx out of OLLA.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

cfg = sixgr.config.defaultConfig();
cfg.phy.linkAdaptation.mode = "amc";
cfg.phy.linkAdaptation.dlPolicy = "baseline";
cfg.phy.linkAdaptation.ulPolicy = "baseline";
cfg.phy.linkAdaptation.outerLoopFlag = true;
cfg.phy.linkAdaptation.deltaMCSPolicy = "olla";
cfg.phy.linkAdaptation.ollaStepDown = 0.9;
cfg.phy.linkAdaptation.ollaStepUp = 0.1;
cfg.phy.linkAdaptation.ollaMarginMinDb = -10;
cfg.phy.linkAdaptation.ollaMarginMaxDb = 10;
cfg.phy.linkAdaptation.targetBLER = 0.1;

policy = sixgr.link.resolveOLLAConfig(cfg);
assert(abs(double(policy.ImpliedTargetBLER) - 0.1) < 1e-12 && ...
    abs(double(policy.ConfiguredTargetBLER) - 0.1) < 1e-12, ...
    "Configured OLLA steps must encode the declared target BLER exactly.");
badTargetCfg = cfg;
badTargetCfg.phy.linkAdaptation.targetBLER = 0.2;
try
    sixgr.link.resolveOLLAConfig(badTargetCfg);
    error("sixgr:test:ExpectedOLLATargetMismatch", ...
        "Mismatched OLLA target/steps must fail closed.");
catch ME
    assert(string(ME.identifier) == ...
        "sixgr:link:OLLATargetBLERStepMismatch", ...
        "Unexpected typed error for mismatched OLLA target/steps: %s", ...
        string(ME.identifier));
end

scheduler = sixgr.l2.mac.SchedulerRR(cfg, "Direction", "DL");
state = struct("CfgMobility", cfg, "NumUsers", 1, ...
    "DLSchedulers", {{scheduler}}, "ULSchedulers", {{}}, ...
    "DLLinkAdaptationState", {{struct()}}, ...
    "ULLinkAdaptationState", {{struct()}}, ...
    "SlotDuration_s", 5e-4);

% A data row may carry the decoder CRC alongside the CSI measurement, but
% that hidden field is not a delivered HARQ event. It may advance ILLA once
% the CSI report is delivered; it must not advance OLLA.
csiOnlyState = state;
csiReport = struct("CQI", 8, "RI", 1, "PMI", 0, "CRI", 0, ...
    "SINR_dB", -5, "DueSlot", 3, "DeliveredSlot", 3, "SourceSlot", 1, ...
    "ServingCell", 1, "SINRSource", "receiver_post_equalization_sinr", ...
    "SINRValueRole", "measurement", "SINRValueStatus", "measured");
hiddenCRCRow = struct("CRCPass", false, "RV", 0, ...
    "IsRetransmission", false);
[csiOnlyState, adaptedCSI] = ...
    sixgr.truth.CoupledTruthRuntime.applyDeliveredCSIAdaptationRuntime( ...
    csiOnlyState, csiReport, 1, "DL", hiddenCRCRow);
assert(double(adaptedCSI.LinkAdaptationStateUpdateCount) == 1 && ...
    double(adaptedCSI.OLLAUpdateCount) == 0 && ...
    ~logical(adaptedCSI.OLLAFeedbackEligible) && ...
    string(adaptedCSI.OLLAFeedbackExclusionReason) == ...
    "event_not_authorized_for_olla:csi_measurement_delivery" && ...
    ~logical(adaptedCSI.OLLAUpdateAuthorized) && ...
    ~logical(adaptedCSI.OLLAUpdateAppliedAtThisEvent) && ...
    double(adaptedCSI.OLLAUpdateCountBeforeEvent) == 0 && ...
    double(adaptedCSI.OLLAUpdateCountAfterEvent) == 0 && ...
    abs(double(csiOnlyState.DLLinkAdaptationState{1}.DeltaMCS)) < 1e-12, ...
    "Delivered CSI may update ILLA, but a colocated hidden CRC must not update OLLA.");
assert(isfinite(double(adaptedCSI.SchedulerResolvedCQI)) && ...
    abs(double(adaptedCSI.SmoothedCQI) - double(adaptedCSI.SchedulerResolvedCQI)) < 1e-12 && ...
    abs(double(csiOnlyState.DLLinkAdaptationState{1}.SmoothedCQI) - ...
        double(adaptedCSI.SchedulerResolvedCQI)) < 1e-12, ...
    ["The first genuine CQI must initialize the receiver-owned filter " + ...
    "directly; it must not be diluted by a synthetic bootstrap CQI=0."]);

% A scheduler-owned waveform grant must retain the exact applied CSI/ILLA
% decision.  The downstream PDSCH/PUSCH runner replays this immutable
% lineage and must not execute a second adaptation loop or emit blank fields.
grant = struct("Slot", 5, "RNTI", 4101, "MCSIndex", 0, "MCS", 0, ...
    "PRBSet", [], "SymbolAllocation", [2 12]);
grantFeedback = adaptedCSI;
grantFeedback.Valid = true;
grantFeedback.DeliveredSlot = 3;
grantFeedback.OLLAFeedbackEligible = false;
adaptedGrant = sixgr.truth.CoupledTruthRuntime. ...
    applyMeasuredFeedbackAMCToGrantRuntime(grant, grantFeedback, [], cfg, "DL");
assert(logical(adaptedGrant.LinkAdaptationFeedbackApplied) && ...
    double(adaptedGrant.LinkAdaptationAppliedFeedbackSourceSlot) == 1 && ...
    double(adaptedGrant.LinkAdaptationAppliedFeedbackDeliveredSlot) == 3 && ...
    double(adaptedGrant.LinkAdaptationAppliedFeedbackAgeSlots) == 4 && ...
    isfinite(double(adaptedGrant.AppliedLinkAdaptationCQIBasedMCS)) && ...
    double(adaptedGrant.AppliedLinkAdaptationMCS) == double(adaptedGrant.MCSIndex), ...
    "Frozen grants must preserve exact applied link-adaptation lineage.");

% A pre-existing nonfinite CQIBasedMCS field must not shadow the exact
% decision produced by the current measured feedback event.
grantWithBlankCQIMCS = grant;
grantWithBlankCQIMCS.CQIBasedMCS = NaN;
adaptedBlankCQIMCSGrant = sixgr.truth.CoupledTruthRuntime. ...
    applyMeasuredFeedbackAMCToGrantRuntime( ...
    grantWithBlankCQIMCS, grantFeedback, [], cfg, "UL");
assert(isfinite(double(adaptedBlankCQIMCSGrant.AppliedLinkAdaptationCQIBasedMCS)), ...
    ["A blank legacy CQIBasedMCS field must not erase the current exact " + ...
     "measured-CQI mapping on a frozen UL grant."]);

firstTransmissionNACK = localFeedback(false, 0, false, 7);
state = sixgr.truth.CoupledTruthRuntime.updateSchedulerAfterFeedbackRuntime( ...
    state, firstTransmissionNACK, "DL");
afterFirstTransmission = state.DLLinkAdaptationState{1};
assert(abs(double(afterFirstTransmission.DeltaMCS) + 0.9) < 1e-12 && ...
    afterFirstTransmission.OLLAUpdateCount == 1, ...
    "A first-transmission NACK must apply exactly one receiver-owned OLLA down-step.");
[schedulerDelta, schedulerCount] = scheduler.getOLLAMCSDelta(4101);
assert(schedulerDelta == 0 && schedulerCount == 0, ...
    "The coupled runtime must not maintain a duplicate scheduler-local OLLA state.");

retransmissionACK = localFeedback(true, 2, true, 11);
state = sixgr.truth.CoupledTruthRuntime.updateSchedulerAfterFeedbackRuntime( ...
    state, retransmissionACK, "DL");
afterRetransmission = state.DLLinkAdaptationState{1};
assert(abs(double(afterRetransmission.DeltaMCS) - double(afterFirstTransmission.DeltaMCS)) < 1e-12 && ...
    afterRetransmission.OLLAUpdateCount == 1, ...
    ["A retransmission ACK must not update first-transmission OLLA. " + ...
    "The coupled runtime must preserve RV and IsRetransmission at the scheduler boundary."]);

nextNewTransmissionACK = localFeedback(true, 0, false, 15);
state = sixgr.truth.CoupledTruthRuntime.updateSchedulerAfterFeedbackRuntime( ...
    state, nextNewTransmissionACK, "DL");
afterNextNewTransmission = state.DLLinkAdaptationState{1};
assert(abs(double(afterNextNewTransmission.DeltaMCS) + 0.8) < 1e-12 && ...
    afterNextNewTransmission.OLLAUpdateCount == 2, ...
    "A later first-transmission ACK must apply exactly one configured OLLA up-step.");

% Received UCI failure is not a decoded NACK about the data channel.
dtx=localFeedback(false,0,false,19);
dtx.FeedbackOutcome="DTX";
state=sixgr.truth.CoupledTruthRuntime.updateSchedulerAfterFeedbackRuntime(state,dtx,"DL");
afterDTX=state.DLLinkAdaptationState{1};
assert(afterDTX.DeltaMCS==afterNextNewTransmission.DeltaMCS && ...
    afterDTX.OLLAUpdateCount==2 && ~afterDTX.LastOLLAFeedbackEligible && ...
    string(afterDTX.LastOLLAFeedbackExclusionReason)=="no_ack_nack_feedback");
% Standalone scheduler-local OLLA follows the same outcome distinction.
standalone=sixgr.l2.mac.SchedulerRR(cfg,"Direction","DL");
standalone.updateAfterRx(struct('RNTI',4101,'TBSBits',800,'Ack',false, ...
    'Outcome','DTX','RV',0,'IsRetransmission',false));
[delta,count]=standalone.getOLLAMCSDelta(4101);
assert(delta==0 && count==0);

% The receiver-owned CQI/ILLA state and OLLA state have different update
% denominators. Every valid CQI can advance the adaptation state, but an
% RV>0/retransmission outcome must not be counted as an OLLA observation.
cfg.phy.linkAdaptation.innerLoopFlag = true;
firstMetrics = struct("CQI", 8, "RI", 1, "CRCPass", false, ...
    "RV", 0, "IsRetransmission", false);
[firstDecision, adaptationState] = sixgr.link.computeLinkAdaptationDecision( ...
    cfg, "DL", firstMetrics);
assert(firstDecision.OLLAFeedbackEligible && firstDecision.OLLAUpdateCount == 1, ...
    "First-transmission NACK must be explicitly eligible for receiver-owned OLLA.");
firstStateCount = double(firstDecision.StateUpdateCount);

retxMetrics = struct("CQI", 9, "RI", 1, "CRCPass", true, ...
    "RV", 2, "IsRetransmission", true);
[retxDecision, adaptationState] = sixgr.link.computeLinkAdaptationDecision( ...
    cfg, "DL", retxMetrics, "AdaptationState", adaptationState);
assert(double(retxDecision.StateUpdateCount) > firstStateCount && ...
    double(retxDecision.OLLAUpdateCount) == 1 && ...
    ~logical(retxDecision.OLLAFeedbackEligible) && ...
    string(retxDecision.OLLAFeedbackExclusionReason) == "harq_retransmission_feedback_excluded", ...
    ["A retransmission may update measured CQI/ILLA state, but must not " + ...
    "increment or move OLLA."]);

nextMetrics = struct("CQI", 9, "RI", 1, "CRCPass", true, ...
    "RV", 0, "IsRetransmission", false);
[nextDecision, ~] = sixgr.link.computeLinkAdaptationDecision( ...
    cfg, "DL", nextMetrics, "AdaptationState", adaptationState);
assert(nextDecision.OLLAFeedbackEligible && nextDecision.OLLAUpdateCount == 2, ...
    "The next first-transmission ACK must increment the independent OLLA counter.");

% SRS is also a measured CSI delivery event.  Both FDD UL and TDD UL must
% initialize the same receiver-owned CQI/ILLA state used by later HARQ
% feedback.  Historically this path copied only MCSIndex, leaving
% CQIBasedMCS nonfinite so a NACK could not lower the next grant.
for duplexMode = ["FDD", "TDD"]
    srsCfg = cfg;
    srsCfg.scenario.duplex.mode = char(duplexMode);
    % TPMI is a CP-OFDM/codebook quantity.  Keep the fixture on the
    % production CP-OFDM path instead of asking a transform-precoded PUSCH
    % (where TPMI is not defined) to preserve a finite codebook index.
    srsCfg.phy.pusch.transformPrecoding = false;
    srsCfg.phy.linkAdaptation.ulSRSToPUSCHLayerSINRPolicy = ...
        "reference_signal_wideband_with_backoff";
    srsCfg.phy.linkAdaptation.ulSRSToPUSCHSINRBackoff_dB = 0;
    srsCfg.phy.linkAdaptation.ulReferenceSignalSchedulingBackoff_dB = 0;
    srsCfg.phy.srs.minWidebandCoverageFractionForMCS = 0.8;
    ulScheduler = sixgr.l2.mac.SchedulerRR(srsCfg, "Direction", "UL");
    emptyLatest = sixgr.truth.CoupledTruthRuntime.emptyLatestFeedbackRowRuntime();
    srsState = struct("CfgMobility", srsCfg, "NumUsers", 1, ...
        "DLSchedulers", {{}}, "ULSchedulers", {{ulScheduler}}, ...
        "DLLinkAdaptationState", {{struct()}}, ...
        "ULLinkAdaptationState", {{struct()}}, ...
        "LatestDLFeedback", emptyLatest, ...
        "LatestULFeedback", emptyLatest, ...
        "PendingCSITable", table(), "SlotDuration_s", 5e-4);
    srsRow = struct("SINR_dB", 15, "WidebandCQI", 12, ...
        "CQIDerivedMCS", 20, "CQIDerivedTargetCodeRate", 0.5547, ...
        "CQIDerivedModulation", "64QAM", "RIEstimate", 1, ...
        "TPMIEstimate", 0, "ServingCell", 1, ...
        "SRSBandwidthCoverageStatus", "full_band", ...
        "SRSBandwidthFraction", 1);
    srsState = sixgr.truth.CoupledTruthRuntime. ...
        updateLatestULFeedbackFromSRSTrialRuntime(srsState, 1, srsRow, 4);
    measuredFeedback = srsState.LatestULFeedback(1);
    initialMCS = double(measuredFeedback.MCSIndex);
    assert(isfinite(double(measuredFeedback.CQIBasedMCS)) && ...
        isfinite(double(measuredFeedback.InstantaneousCQIMCS)) && ...
        isfinite(initialMCS) && logical(measuredFeedback.InnerLoopEnabled) && ...
        logical(measuredFeedback.OuterLoopEnabled) && ...
        double(measuredFeedback.SourceSlot) == 4 && ...
        double(measuredFeedback.DueSlot) == 4 && ...
        double(measuredFeedback.DeliveredSlot) == 4, ...
        "%s SRS must initialize receiver-owned ILLA/OLLA state.", duplexMode);

    ulNACK = localFeedback(false, 0, false, 4);
    srsState = sixgr.truth.CoupledTruthRuntime. ...
        updateSchedulerAfterFeedbackRuntime(srsState, ulNACK, "UL");
    afterNACK = srsState.LatestULFeedback(1);
    assert(double(srsState.ULLinkAdaptationState{1}.OLLAUpdateCount) == 1 && ...
        double(srsState.ULLinkAdaptationState{1}.DeltaMCS) < 0 && ...
        isfinite(double(afterNACK.MCSIndex)) && ...
        double(afterNACK.MCSIndex) <= initialMCS, ...
        "%s first-transmission UL NACK must lower/hold the next new-data MCS.", duplexMode);

    % A later SRS update must retain the receiver-owned negative OLLA margin
    % instead of restoring the raw high CQI-derived MCS.
    srsState = sixgr.truth.CoupledTruthRuntime. ...
        updateLatestULFeedbackFromSRSTrialRuntime(srsState, 1, srsRow, 5);
    assert(double(srsState.LatestULFeedback(1).DeltaMCS) < 0 && ...
        double(srsState.LatestULFeedback(1).MCSIndex) <= initialMCS, ...
        "%s later SRS must preserve the HARQ-derived OLLA down-margin.", duplexMode);
end

% A high pilot-reconstruction SRS metric is not an absolute PUSCH
% data-channel SINR.  The minimum-layer policy must fail closed when the
% power-plane-anchored prediction is absent, while still retaining the
% independently measured RI/TPMI spatial recommendation.
strictSrsCfg = cfg;
strictSrsCfg.scenario.duplex.mode = "TDD";
strictSrsCfg.phy.pusch.transformPrecoding = false;
strictSrsCfg.phy.linkAdaptation.ulSRSToPUSCHLayerSINRPolicy = ...
    "minimum_layer_mean_post_equalization";
strictSrsCfg.phy.srs.minWidebandCoverageFractionForMCS = 0.8;
strictScheduler = sixgr.l2.mac.SchedulerRR(strictSrsCfg, "Direction", "UL");
strictLatest = sixgr.truth.CoupledTruthRuntime.emptyLatestFeedbackRowRuntime();
strictState = struct("CfgMobility", strictSrsCfg, "NumUsers", 1, ...
    "DLSchedulers", {{}}, "ULSchedulers", {{strictScheduler}}, ...
    "DLLinkAdaptationState", {{struct()}}, ...
    "ULLinkAdaptationState", {{struct()}}, ...
    "LatestDLFeedback", strictLatest, "LatestULFeedback", strictLatest, ...
    "PendingCSITable", table(), "SlotDuration_s", 5e-4);
unanchoredSrsRow = struct("SINR_dB", 32.5, "WidebandCQI", 15, ...
    "CQIDerivedMCS", 28, "CQIDerivedTargetCodeRate", 0.9258, ...
    "CQIDerivedModulation", "64QAM", "RIEstimate", 1, ...
    "TPMIEstimate", 0, "ServingCell", 1, ...
    "SRSBandwidthCoverageStatus", "full_band", ...
    "SRSBandwidthFraction", 1, ...
    "PredictedPUSCHMinimumLayerSINR_dB", NaN, ...
    "PredictedPUSCHPostEqSINRValueStatus", "NOT_AVAILABLE");
strictState = sixgr.truth.CoupledTruthRuntime. ...
    updateLatestULFeedbackFromSRSTrialRuntime( ...
    strictState, 1, unanchoredSrsRow, 4);
strictFeedback = strictState.LatestULFeedback(1);
assert(~logical(strictFeedback.Valid) && ...
    ~isfinite(double(strictFeedback.MCSIndex)) && ...
    isfinite(double(strictFeedback.RI)) && isfinite(double(strictFeedback.PMI)), ...
    sprintf(['Unanchored SRS residual quality must not install CQI/MCS ' ...
    'into the PUSCH scheduler, but measured RI/TPMI must remain available. ' ...
    'Observed Valid=%s, MCS=%s, RI=%s, PMI=%s.'], ...
    mat2str(strictFeedback.Valid), mat2str(strictFeedback.MCSIndex), ...
    mat2str(strictFeedback.RI), mat2str(strictFeedback.PMI)));

ok = true;
end

function row = localFeedback(ack, rv, isRetransmission, sourceSlot)
row = struct( ...
    "UEIndex", 1, ...
    "ServingCell", 1, ...
    "RNTI", 4101, ...
    "TBSBits", 2048, ...
    "Ack", logical(ack), ...
    "HarqID", NaN, ...
    "RV", double(rv), ...
    "IsRetransmission", logical(isRetransmission), ...
    "SourceSlot", double(sourceSlot));
end
