function ok = testKPIDirectionIsolation()
%TESTKPIDIRECTIONISOLATION KPI reconstruction must reject cross-direction rows.

setup6GRSimToolkit("Verbose", false);

raw = localRawFixture();
raw.UL.Direction(2) = "DL";
out = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw, ...
    "RunId", "direction_isolation_negative", ...
    "ScenarioName", "unit_fixture", ...
    "StrictMode", true);

ulAudit = out.DirectionIsolationAudit(string(out.DirectionIsolationAudit.Direction) == "UL", :);
assert(height(ulAudit) == 1 && strcmp(string(ulAudit.Status(1)), "fail"), ...
    "UL KPI direction audit must fail when a UL source contains DL rows.");
assert(~logical(out.SummaryAliases.KPIReconciliationPass(1)), ...
    "Legacy KPI summary must not pass reconciliation with mixed-direction UL rows.");

raw = localRawFixture();
out = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw, "StrictMode", true);
assert(all(strcmp(string(out.DirectionIsolationAudit.Status), "pass")), ...
    "Clean UL/DL source tables must pass direction isolation.");

ok = true;
end

