    repmat("UL", 2, 1), [7.952; 0], [true; false], [0; 120], [7952; 8000], ...
    [7952; 8000], [7952; 0], [1; 2], [1; 2], ["ul_tb_1"; "ul_tb_2"], [0; 0], [0; 0], [0; 0], ...
    [1; 1], [1; 2], ...
