function testWaveCFixedSweepUsesExactMasterAuthority(testCase)
repositoryRoot=fileparts(fileparts(mfilename("fullpath")));
scenarioPath=fullfile(repositoryRoot,"simulator","configs","scenarios", ...
    "lls_webgui_full_stack_sinr_geometry_qualification.yaml");
scfg=sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
profile=sixgr.integration.qualification. ...
    FullStackQualificationProfile.load(scfg);
root=string(tempname);
mkdir(root);
cleanup=onCleanup(@()localCleanup(root)); %#ok<NASGU>
cfg=sixgr.lls6g.buildInternalConfig(scfg,root);
campaign=cfg.validation.fixed_link_campaign;
preset=profile.PresetConfiguration;
seeds=double(preset.fixed_snr_seeds(:).');
trialsPerSeed=double( ...
    preset.fixed_tbs_per_point_per_direction_per_seed);
verifyEqual(testCase,double(campaign.snr_db(:).'),[-8 -4 0 4 10]);
verifyEqual(testCase,double(campaign.seeds(:).'),seeds);
verifyEqual(testCase,double(campaign.trials_per_drop),trialsPerSeed);
verifyEqual(testCase,double(campaign.min_tb_per_point), ...
    trialsPerSeed*numel(seeds));
verifyEqual(testCase,double(campaign.max_tb_per_point), ...
    trialsPerSeed*numel(seeds));
verifyEqual(testCase,logical(cfg.phy.pdsch.enablePTRS), ...
    logical(campaign.enable_ptrs));
verifyEqual(testCase,logical(cfg.phy.pusch.enablePTRS), ...
    logical(campaign.enable_ptrs));
verifyGreaterThanOrEqual(testCase, ...
    double(cfg.antenna.ue.numElements), ...
    double(cfg.phy.pusch.numAntennaPorts));
verifyGreaterThanOrEqual(testCase, ...
    double(cfg.scenario.ue.nTxAnt), ...
    double(cfg.phy.pusch.numAntennaPorts));
conflict=scfg.toStruct();
conflict.reference_signals.ptrs_enabled=false;
verifyError(testCase,@()sixgr.lls6g.config.validateScenarioConfig( ...
    conflict,"Kind","scenario","AllowPartial",false, ...
    "Context","Wave-C PUSCH PT-RS authority mutation"), ...
    "sixgr:lls6g:config:FixedLinkMasterPTRSAuthorityConflict");
antennaConflict=scfg.toStruct();
antennaConflict.antenna_and_array.ue_num_antenna_elements=1;
verifyError(testCase,@()sixgr.lls6g.config.validateScenarioConfig( ...
    antennaConflict,"Kind","scenario","AllowPartial",false, ...
    "Context","Wave-C PUSCH antenna authority mutation"), ...
    "sixgr:lls6g:config:FixedLinkMasterPUSCHAntennaAuthorityConflict");
end

function testWaveCExporterMapsRuntimeColumnsOnly(testCase)
root=string(tempname);
mkdir(root);
cleanup=onCleanup(@()localCleanup(root)); %#ok<NASGU>
snr=[-8;-4;0;4;10];
curve=table(snr,ones(5,1),ones(5,1),(1:5)', ...
    ones(5,1),[1;1;0;0;0], ...
    [1;1;0;0;0],[0.2;0.2;0;0;0],[1;1;0.8;0.8;0.8], ...
    [0.4;0.4;0.4;0.4;0.4],repmat("AWGN",5,1), ...
    repmat("FIXED_TRIAL_BUDGET_COMPLETE",5,1),false(5,1), ...
    'VariableNames',{'SNR_dB','MCSIndex','ConfiguredRank', ...
    'PointIndex','TrialCount','FailureCount','Value','CI_Low', ...
    'CI_High','CI_HalfWidth','ConfiguredChannelModel', ...
    'StopReason','Incomplete'});
trials=table(snr,snr,repmat("receiver_post_eq",5,1),true(5,1), ...
    ones(5,1),ones(5,1),100*ones(5,1), ...
    200*ones(5,1),300*ones(5,1),0.1*ones(5,1), ...
    [10;10;0;0;0],100*ones(5,1), ...
    logical([0;0;1;1;1]),-20*ones(5,1), ...
    2*ones(5,1),(1:5)',ones(5,1),repmat("AWGN",5,1), ...
    repmat("QPSK",5,1),ones(5,1),false(5,1),false(5,1), ...
    'VariableNames',{'ConfiguredSNR_dB','PostEqSINR_dB', ...
    'PostEqSINRSource','PostEqSINRReceiverDerived', ...
    'FixedLinkConfiguredRank','FixedLinkConfiguredLayers', ...
    'DataRECount','RateMatchedBits','EncodedBits','EVM_rms', ...
    'BitErrors','BitsCompared','CRCPass','NMSE_dB', ...
    'DecoderIterations','FixedLinkPointIndex', ...
    'FixedLinkTrialIndex','FixedLinkConfiguredChannelModel', ...
    'Modulation','UEIndex','InterferenceCovarianceAvailable', ...
    'TransformPrecodingApplied'});
campaign=struct("DLTrials",trials,"ULTrials",trials, ...
    "DLBlerCurve",curve,"ULBlerCurve",curve);
cfg=struct("validation",struct("fixed_link_campaign", ...
    struct("confidence_level",0.95,"min_errors_for_ci",0)), ...
    "phy",struct("pusch",struct("frequencyHopping", ...
    struct("mode","none"))));
out=sixgr.integration.qualification.QualificationFixedSweepExporter. ...
    export(campaign,root,"fixture-runtime-columns",cfg);
verifyTrue(testCase,out.Passed);
for name=["pdsch_receiver_metrics.csv","pusch_receiver_metrics.csv", ...
        "pdsch_bler_curve.csv","pusch_bler_curve.csv", ...
        "pdsch_bler_vs_snr.png","pusch_bler_vs_snr.png", ...
        "pdsch_per_layer_sinr.png","pusch_per_layer_sinr.png"]
    verifyTrue(testCase,isfile(fullfile(root,name)),name);
end
end

