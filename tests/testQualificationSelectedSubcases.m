function testPreflightRunsWithoutOtherGroups(testCase)
root=string(tempname);
cleanup=onCleanup(@()rmdir(root,"s")); %#ok<NASGU>
repositoryRoot=fileparts(fileparts(mfilename("fullpath")));
out=sixgr.integration.qualification.runSelectedSubcases( ...
    ScenarioPath=fullfile(repositoryRoot,"simulator","configs","scenarios", ...
    "lls_webgui_full_stack_sinr_geometry_qualification.yaml"), ...
    Preset="comprehensive_smoke",SubcaseIDs="SC-00", ...
    ParentRunID="qualification-selected-test",OutputRoot=root, ...
    Strict=false);
verifyTrue(testCase,out.CompletedWithoutException);
verifyEqual(testCase,height(out.SubcaseResults),1);
verifyEqual(testCase,out.SubcaseResults.SubcaseID,"SC-00");
verifyTrue(testCase,out.SubcaseResults.Executed);
verifyTrue(testCase,out.SubcaseResults.CorrectnessChecked);
verifyFalse(testCase,out.SubcaseResults.EvidencePresent);
verifyEqual(testCase,out.SubcaseResults.Status,"FAIL");
verifyTrue(testCase,isfile(fullfile(root,"qualification_evidence", ...
    "selected_subcase_manifests","preflight_execution_manifest.csv")));
end

