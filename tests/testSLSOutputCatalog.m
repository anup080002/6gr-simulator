function ok = testSLSOutputCatalog()
%TESTSLSOUTPUTCATALOG Ensure persisted SLS runs emit the mandatory bundle.

setup6GRSimToolkit("Verbose", false);

cfg = sixgr.config.defaultConfig();
cfg.run.shortRun = true;
cfg.run.strictMode = false;
cfg.run.useMex = false;
cfg.run.seed = 11;
cfg.system.phyBackend = "waveform";
cfg.outputs.saveCSV = true;
cfg.outputs.saveMAT = true;
cfg.outputs.saveFigures = true;
cfg.outputs.saveFIG = true;

cfg.scenario.layout.nSites = 1;
cfg.scenario.layout.nSectorsPerSite = 1;
cfg.scenario.layout.wrapAround = false;
cfg.scenario.ue.nUE = 4;
cfg.scenario.nUE = 4;
cfg.scenario.bs.nTxAnt = 1;
cfg.scenario.bs.nRxAnt = 1;
cfg.scenario.ue.nTxAnt = 1;
cfg.scenario.ue.nRxAnt = 1;

cfg.channel.awgnOnly = true;
cfg.channel.model = "AWGN";
cfg.channel.fading.enable = false;

cfg.phy.pdsch.modulation = "QPSK";
cfg.phy.pdsch.codeRate = 0.35;
cfg.phy.pdsch.numLayers = 1;
cfg.phy.pdsch.nLayers = 1;
cfg.phy.pusch.modulation = "QPSK";
cfg.phy.pusch.codeRate = 0.35;
cfg.phy.pusch.numLayers = 1;
cfg.phy.pusch.nLayers = 1;
cfg.mac.scheduler.type = "rr";
cfg = sixgr.config.normalizeConfig(cfg);
sixgr.config.validateConfig(cfg);

runFolder = tempname;
ctx = sixgr.core.SimContext(cfg, "RunFolder", runFolder);
numTTI = 8;
nUE = 4;
res = sixgr.system.SystemLevelRunner.run(ctx, struct( ...
    "NumTTI", numTTI, ...
    "OfferedBitsDL", repmat(4000, numTTI, nUE), ...
    "OfferedBitsUL", zeros(numTTI, nUE), ...
    "PHYBackend", "waveform"));

assert(res.Ok, "System run failed while generating the SLS output catalog.");
assert(isfield(res, "OutputCatalog") && isstruct(res.OutputCatalog), "Missing SLS output catalog metadata.");

mustExist = { ...
    fullfile(runFolder, "manifests"), ...
    fullfile(runFolder, "summaries"), ...
    fullfile(runFolder, "raw"), ...
    fullfile(runFolder, "tables"), ...
    fullfile(runFolder, "traces"), ...
    fullfile(runFolder, "maps"), ...
    fullfile(runFolder, "plots"), ...
    fullfile(runFolder, "comparisons"), ...
    fullfile(runFolder, "debug"), ...
    fullfile(runFolder, "manifests", "run_manifest.yaml"), ...
    fullfile(runFolder, "manifests", "resolved_config.yaml"), ...
    fullfile(runFolder, "manifests", "assumption_report.yaml"), ...
    fullfile(runFolder, "manifests", "cross_check_report.md"), ...
    fullfile(runFolder, "manifests", "cross_check_report.json"), ...
    fullfile(runFolder, "manifests", "system_run_manifest.json"), ...
    fullfile(runFolder, "manifests", "resolved_config.json"), ...
    fullfile(runFolder, "manifests", "runtime_summary.json"), ...
    fullfile(runFolder, "manifests", "environment.json"), ...
    fullfile(runFolder, "summaries", "system_run_summary.md"), ...
    fullfile(runFolder, "tables", "system_kpis.csv"), ...
    fullfile(runFolder, "tables", "sites.csv"), ...
    fullfile(runFolder, "tables", "sectors.csv"), ...
    fullfile(runFolder, "tables", "trps.csv"), ...
    fullfile(runFolder, "tables", "ues.csv"), ...
    fullfile(runFolder, "traces", "system_time_series.csv"), ...
    fullfile(runFolder, "traces", "ue_trajectories.parquet"), ...
    fullfile(runFolder, "maps", "system_topology_snapshot.csv"), ...
    fullfile(runFolder, "maps", "site_layout.png"), ...
    fullfile(runFolder, "maps", "attachment_map.png"), ...
    fullfile(runFolder, "maps", "handover_boundaries.png"), ...
    fullfile(runFolder, "maps", "serving_beam_map.png"), ...
    fullfile(runFolder, "comparisons", "comparison_manifest.csv"), ...
    fullfile(runFolder, "debug", "output_catalog_inventory.csv") ...
    };

for i = 1:numel(mustExist)
    assert(exist(mustExist{i}, "file") == 2 || isfolder(mustExist{i}), ...
        "Missing SLS output catalog artifact: %s", mustExist{i});
end

plotFiles = dir(fullfile(runFolder, "plots", "*.png"));
assert(~isempty(plotFiles), "Expected at least one SLS plot in the output catalog.");

runManifestText = fileread(fullfile(runFolder, "manifests", "run_manifest.yaml"));
requiredRunManifestKeys = { ...
    "run_id:", ...
    "scenario_name:", ...
    "campaign_name:", ...
    "timestamp_start_utc:", ...
    "timestamp_end_utc:", ...
    "wall_clock_runtime_s:", ...
    "simulation_time_s:", ...
    "simulator_version:", ...
    "git_commit:", ...
    "branch:", ...
    "dirty_repo_flag:", ...
    "hostname:", ...
    "container_id:", ...
    "python:", ...
    "compiler:", ...
    "dependency_versions:", ...
    "random_seeds:", ...
    "config_hash:", ...
    "model_hash:", ...
    "result_hash:" ...
    };
for i = 1:numel(requiredRunManifestKeys)
    assert(contains(runManifestText, requiredRunManifestKeys{i}), ...
        "run_manifest.yaml missing required key: %s", requiredRunManifestKeys{i});
end

assumptionReportText = fileread(fullfile(runFolder, "manifests", "assumption_report.yaml"));
requiredAssumptionKeys = { ...
    "report_name:", ...
    "scenario_name:", ...
    "parameters:", ...
    "parameter:", ...
    "value:", ...
    "units:", ...
    "source_tag:", ...
    "assumption_class:", ...
    "applicability:", ...
    "baseline_status:" ...
    };
for i = 1:numel(requiredAssumptionKeys)
    assert(contains(assumptionReportText, requiredAssumptionKeys{i}), ...
        "assumption_report.yaml missing required key: %s", requiredAssumptionKeys{i});
end

crossCheck = jsondecode(fileread(fullfile(runFolder, "manifests", "cross_check_report.json")));
requiredCrossCheckFields = { ...
    "implemented_features", ...
    "partial_features", ...
    "unsupported_features", ...
    "unused_config_fields", ...
    "hidden_constants", ...
    "missing_outputs", ...
    "non_baseline_assumptions_used", ...
    "not_applicable_outputs" ...
    };
for i = 1:numel(requiredCrossCheckFields)
    assert(isfield(crossCheck, requiredCrossCheckFields{i}), ...
        "cross_check_report.json missing required field: %s", requiredCrossCheckFields{i});
end

requiredGeometryColumns = { ...
    "site_id","sector_id","trp_id","x_m","y_m","z_m","layer_id","carrier_id", ...
    "boresight_deg","mechanical_tilt_deg","electrical_tilt_deg","max_tx_power_dbm", ...
    "antenna_model_id","array_geometry_id","indoor_outdoor","sleep_capable_flag" ...
    };
siteT = readtable(fullfile(runFolder, "tables", "sites.csv"));
sectorT = readtable(fullfile(runFolder, "tables", "sectors.csv"));
trpT = readtable(fullfile(runFolder, "tables", "trps.csv"));
for i = 1:numel(requiredGeometryColumns)
    assert(ismember(requiredGeometryColumns{i}, siteT.Properties.VariableNames), ...
        "sites.csv missing required column: %s", requiredGeometryColumns{i});
    assert(ismember(requiredGeometryColumns{i}, sectorT.Properties.VariableNames), ...
        "sectors.csv missing required column: %s", requiredGeometryColumns{i});
    assert(ismember(requiredGeometryColumns{i}, trpT.Properties.VariableNames), ...
        "trps.csv missing required column: %s", requiredGeometryColumns{i});
end

ueT = readtable(fullfile(runFolder, "tables", "ues.csv"));
requiredUEColumns = { ...
    "ue_id","ue_type","service_profile","start_x_m","start_y_m","start_z_m", ...
    "indoor_outdoor_state","speed_profile","heading","power_class_dbm", ...
    "antenna_model_id","ai_capability_class","mobility_profile_id" ...
    };
for i = 1:numel(requiredUEColumns)
    assert(ismember(requiredUEColumns{i}, ueT.Properties.VariableNames), ...
        "ues.csv missing required column: %s", requiredUEColumns{i});
end

trajT = parquetread(fullfile(runFolder, "traces", "ue_trajectories.parquet"));
requiredTrajectoryColumns = { ...
    "t","ue_id","x_m","y_m","z_m","speed_kmh","heading_deg", ...
    "indoor_outdoor_state","serving_cell_id","serving_beam_id" ...
    };
for i = 1:numel(requiredTrajectoryColumns)
    assert(ismember(requiredTrajectoryColumns{i}, trajT.Properties.VariableNames), ...
        "ue_trajectories.parquet missing required column: %s", requiredTrajectoryColumns{i});
end

ok = true;
end
