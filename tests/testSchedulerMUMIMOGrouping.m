assert(numel(singleReplay) == 1 && ~singleReplay.MUMIMOEnabled && ...
    singleReplay.MUMIMOGroupSize == 1 && isnan(singleReplay.MUMIMOGroupId) && ...
    string(singleReplay.MUMIMOPairingStatus) == ...
        "retransmission_without_current_shared_mu_peer" && ...
    string(singleReplay.MUMIMOPairingEvidenceSource) == ...
        "no_current_shared_prb_mu_peer" && ...
    singleReplay.PriorMUMIMOGroupSize == 2 && ...
    isfinite(singleReplay.PriorMUMIMOGroupId) && ...
    string(singleReplay.MUMIMOSpatialDesignEvidenceSource) == ...
        "causal_measured_srs_complete_peer_subspace_reciprocity_phase_only_hybrid_and_frozen_baseband", ...
    "An unpaired HARQ replay must not retain stale current MU execution labels.");
assert(isequal(double(singleReplay.PHYGrant.PrecodingState.HybridElementToPortMatrix), F) && ...
    string(singleReplay.PHYGrant.PrecodingState.HybridRFDesignPolicy) == ...
        "fixed_configured_matrix", ...
    ["An unpaired replay of a measured-MU HARQ TB must retain the exact " ...
     "YAML-owned role-level RF architecture even when the scheduler config " ...
     "still carries a stale signal-level beam selection."]);

% The prior immutable PHYGrant, not MU labels, is the authority for an
% orthogonal HARQ replay. Strip every measured-MU provenance field from an
% otherwise valid first transmission and retain only its frozen spatial
% contract. This reproduces a single-user replay after the runtime has
% replaced the scheduler config's signal-level beam mirror.
priorOnlyHARQ = sixgr.l2.mac.HARQEntity(staleSingleUserCfg, ...
    "Direction", "DL", "NumProcesses", 4, "MaxRetx", 3);
priorOnlyScheduler = sixgr.l2.mac.SchedulerPF(staleSingleUserCfg, ...
    "Direction", "DL", "HARQ", priorOnlyHARQ);
priorOnlyOriginal = original;
priorOnlyOriginal.MUMIMOEnabled = false;
priorOnlyOriginal.MUMIMOGroupSize = 1;
priorOnlyOriginal.MUMIMOGroupId = NaN;
priorOnlyOriginal.MUMIMOSpatialDesignContractVersion = "";
priorOnlyOriginal.MUMIMOSpatialDesignEvidenceSource = "";
priorOnlyOriginal.MUMIMOPairingEvidenceSource = "";
priorOnlyOriginal.HARQTBContext = struct( ...
    "OriginalNumLayers", double(priorOnlyOriginal.NumLayers), ...
    "TBSBits", double(priorOnlyOriginal.TBSBits), ...
    "HARQProcessId", double(priorOnlyOriginal.HARQ.HarqID), ...
    "NDI", logical(priorOnlyOriginal.HARQ.NDI), ...
    "NDIEpoch", double(sixgr.util.structGet( ...
        priorOnlyOriginal.HARQ, "NDIEpoch", 1)));
priorOnlyHARQ.onTx(double(priorOnlyOriginal.RNTI), ...
    double(priorOnlyOriginal.HARQ.HarqID), ...
    zeros(round(double(priorOnlyOriginal.TBSBits)), 1, "uint8"), ...
    priorOnlyOriginal, 0);
priorOnlyHARQ.onFeedback(double(priorOnlyOriginal.RNTI), ...
    double(priorOnlyOriginal.HARQ.HarqID), "NACK", ...
    "SourceSlot", 0, "FeedbackSlot", 4);
priorOnlyUE = ue([1 3]);
priorOnlyUE(2).DLBufferBytes = 0;
priorOnlyReplay = priorOnlyScheduler.schedule(5, priorOnlyUE, ...
    struct("PRBSet", 0:23, "SymbolAllocation", [2 12]));
priorOnlyReplay = priorOnlyReplay( ...
    [priorOnlyReplay.RNTI] == priorOnlyOriginal.RNTI);
assert(numel(priorOnlyReplay) == 1 && ...
    logical(priorOnlyReplay.IsRetransmission) && ...
    isequal(double(priorOnlyReplay.PHYGrant.PrecodingState.HybridElementToPortMatrix), ...
        double(priorOnlyOriginal.PHYGrant.PrecodingState.HybridElementToPortMatrix)) && ...
    string(priorOnlyReplay.PHYGrant.PrecodingState.SelectedMatrixSHA256) == ...
        string(priorOnlyOriginal.PHYGrant.PrecodingState.SelectedMatrixSHA256), ...
    ["A single-user HARQ scheduler replay must project and preserve the " ...
     "previous immutable PHYGrant architecture and physical precoder even " ...
     "when no MU provenance label remains."]);

ok = true;
end

function ue = localUEs(pmi, cqi)
n = numel(pmi);
ue = repmat(struct( ...
    "RNTI", 0, ...
    "UEIndex", 0, ...
    "ServingCell", 1, ...
    "DLBufferBytes", 20000, ...
    "CQI", 0, ...
    "RI", 2, ...
    "PMI", 0, ...
    "CRI", 0, ...
    "MeasuredSINR_dB", 15, ...
    "FeedbackValid", true, ...
    "CausalFeedbackUsable", true, ...
    "MUMIMOSpatialSignature", [], ...
    "MUMIMOSpatialSignatureSHA256", "", ...
    "MUMIMOSpatialSignatureSource", "", ...
    "MUMIMOSpatialSignatureSourceSlot", NaN, ...
    "MUMIMOSpatialSignatureAgeSlots", NaN, ...
    "MUMIMOSpatialSignatureConsumerRuntimeSlot", NaN, ...
    "MUMIMOSpatialSignatureMeasurementDirection", "", ...
    "MUMIMOSpatialSignatureReciprocityMode", "", ...
    "MUMIMOSpatialSignatureValid", false, ...
    "HeadOfLineDelay_ms", 1), n, 1);
for index = 1:n
    ue(index).RNTI = index;
    ue(index).UEIndex = index;
    ue(index).CQI = cqi(index);
    ue(index).PMI = pmi(index);
end
end

function ue = localBindMeasuredSpatialSignatures(ue, direction, sourceSlot)
direction = upper(string(direction));
for index = 1:numel(ue)
    w = ue(index).MUMIMOSpatialSignature;
    if isempty(w)
        continue;
    end
    ue(index).MUMIMOSpatialSignatureSHA256 = char( ...
        sixgr.phy.mimo.MatrixContract.digest(w));
    ue(index).MUMIMOSpatialSignatureSource = ...
        "measured_srs_receiver_channel_estimate_pilot_re_frequency_selective_complete_detectable_subspace";
    ue(index).MUMIMOSpatialSignatureSourceSlot = double(sourceSlot) + 1;
    ue(index).MUMIMOSpatialSignatureAgeSlots = 0;
    ue(index).MUMIMOSpatialSignatureConsumerRuntimeSlot = double(sourceSlot) + 1;
    ue(index).MUMIMOSpatialSignatureMeasurementDirection = "UL";
    if direction == "DL"
        ue(index).MUMIMOSpatialSignatureReciprocityMode = "tdd_reciprocity";
    else
        ue(index).MUMIMOSpatialSignatureReciprocityMode = "direct_ul_srs";
    end
    ue(index).MUMIMOSpatialSignatureValid = true;
end
end

