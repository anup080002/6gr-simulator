function ok = testSchedulerMUMIMOGrouping()
%TESTSCHEDULERMUMIMOGROUPING Validate causal shared-PRB PF grouping.

setup6GRSimToolkit("Verbose", false);

tmpRoot = string(tempname);
mkdir(tmpRoot);
cleanup = onCleanup(@()localRemoveTree(tmpRoot)); %#ok<NASGU>
scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "webgui_sinr_sweep_64x4_mu_mimo_repair_slice.yaml");
scenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scenario, fullfile(tmpRoot, "run"));
assert(string(cfg.phy.pdsch.precoding.normalizationConvention) == ...
    "unit_frobenius" && ...
    string(cfg.phy.pusch.precoding.normalizationConvention) == ...
    "unit_frobenius", ...
    ["Both master-YAML data-channel power conventions must reach the " ...
     "production frozen-grant path without a MATLAB default."]);

% Four measured-CSI candidates are ordered equally by PF.  UE 2 shares
% UE 1's PMI, while UE 3 is the first compatible codebook candidate.  The
% scheduler must search beyond the two-user transmission cap and then cap
% the selected group at two transmitted users.
ue = localUEs([0 0 1 0], [10 10 10 10]);
nRF = double(cfg.runtime.antenna.gnb.NumTxRFChains);
muArch = sixgr.rf.AntennaArrayFactory.resolvePortArchitecture(cfg, "bs", ...
    "Signal", "PDSCH", "NumElements", 64, "NumPorts", nRF, ...
    "NumRFChains", nRF, "MinimumPorts", 4, ...
    "MatrixAuthorityScope", "role_only");
F = double(muArch.HybridElementToPortMatrix);
element = (0:63).';
qCorrelatedA = [exp(1i .* 2 .* pi .* element ./ 64), ...
    exp(1i .* 4 .* pi .* element ./ 64), ...
    exp(1i .* 6 .* pi .* element ./ 64), ...
    exp(1i .* 8 .* pi .* element ./ 64)] ./ sqrt(64);
qIndependent = [exp(1i .* 10 .* pi .* element ./ 64), ...
    exp(1i .* 14 .* pi .* element ./ 64), ...
    exp(1i .* 18 .* pi .* element ./ 64), ...
    exp(1i .* 22 .* pi .* element ./ 64)] ./ sqrt(64);
[qCorrelatedB, ~] = qr(0.65 .* qCorrelatedA + 0.75 .* qIndependent, 0);
rawLeakage_dB = 10 * log10(norm(qCorrelatedA' * qCorrelatedB, "fro")^2 / 2);
designed = sixgr.phy.mimo.designMeasuredMUMIMOPair( ...
    qCorrelatedA, qCorrelatedB, cfg, "DL", 2, 2);
assert(rawLeakage_dB > -15 && designed.Compatible && ...
    designed.WorstLeakage_dB <= -15 && ...
    designed.MinimumDesiredGainObserved_dB >= -30, ...
    "A correlated measured pair must pass only after executable block diagonalization, not by relabeling raw overlap.");
assert(isequal(designed.HybridElementToPortMatrix, F) && ...
    string(designed.HybridRFDesignStatus) == "fixed_configured_hybrid_matrix", ...
    ["Measured DL MU design must retain the exact YAML-configured 64x32 " ...
     "phase-only RF hardware matrix and adapt only its baseband block diagonalizer."]);
assert(string(designed.ContractVersion) == "MeasuredMUMIMOPairDesign/v13" && ...
    string(designed.SpatialSignatureSubspaceMode) == ...
        "complete_detectable_subspace" && ...
    abs(norm(designed.Member1PrecoderPhysical, "fro")^2 - 1) <= 1e-12 && ...
    abs(norm(designed.Member2PrecoderPhysical, "fro")^2 - 1) <= 1e-12 && ...
    norm(designed.HybridElementToPortMatrix * ...
        designed.Member1PrecoderLogicalPorts - ...
        designed.Member1PrecoderPhysical, "fro") <= 1e-12 && ...
    norm(designed.HybridElementToPortMatrix * ...
        designed.Member2PrecoderLogicalPorts - ...
        designed.Member2PrecoderPhysical, "fro") <= 1e-12, ...
    "Rank-2 MU design must allocate unit total per-UE power and preserve the exact RF/baseband factorization.");

% Fully digital arrays are not hybrid arrays.  Four independently
% controlled element/RF dimensions must nevertheless support an exact
% measured rank-2 + rank-2 block-diagonalizing precoder.  Conversely, two
% UEs with the same measured subspace remain physically incompatible.
digitalCfg = struct();
digitalCfg.mac.scheduler.muMimoPrecoderLeakageThreshold_dB = -15;
digitalCfg.mac.scheduler.muMimoMinimumDesiredSubspaceGain_dB = -30;
digitalCfg.mac.scheduler.muMimoPhaseOnlyProjectionMaxIterations = 50;
digitalCfg.mac.scheduler.muMimoPhaseOnlyProjectionTolerance = 1e-10;
digitalCfg.mac.scheduler.muMimoSpatialSignatureMode = ...
    "complete_detectable_subspace";
digitalCfg.runtime.antenna.gnb.NumTxRFChains = 4;
qDigitalA = eye(4, 2);
qDigitalB = eye(4);
qDigitalB = qDigitalB(:, 3:4);
digitalDesigned = sixgr.phy.mimo.designMeasuredMUMIMOPair( ...
    qDigitalA, qDigitalB, digitalCfg, "DL", 2, 2, "direct_dl_csirs");
assert(digitalDesigned.Compatible && ...
    string(digitalDesigned.TransmitArchitecture) == ...
        "fully_digital_element_control" && ...
    string(digitalDesigned.HybridRFDesignPolicy) == ...
        "fully_digital_direct_element_control" && ...
    string(digitalDesigned.HybridRFDesignStatus) == ...
        "fully_digital_full_rank_port_to_element_mapping" && ...
    isequal(size(digitalDesigned.Member1PrecoderPhysical), [4 2]) && ...
    isequal(size(digitalDesigned.Member2PrecoderPhysical), [4 2]), ...
    ["A square full-rank four-element/four-RF-chain array must execute " ...
     "measured fully-digital MU precoding without being mislabeled hybrid."]);
digitalIncompatible = sixgr.phy.mimo.designMeasuredMUMIMOPair( ...
    qDigitalA, qDigitalA, digitalCfg, "DL", 2, 2, "direct_dl_csirs");
assert(~digitalIncompatible.Compatible, ...
    ["Identical per-UE measured subspaces must remain incompatible; the " ...
     "fully-digital path must not fabricate spatial separability."]);
fddDesigned = sixgr.phy.mimo.designMeasuredMUMIMOPair( ...
    qCorrelatedA, qCorrelatedB, cfg, "DL", 2, 2, "direct_dl_csirs");
assert(fddDesigned.Compatible && ...
    string(fddDesigned.SpatialAuthorityMode) == "direct_dl_csirs" && ...
    contains(string(fddDesigned.MetricSource), "fdd_csirs_direct_transmit") && ...
    contains(string(fddDesigned.EvidenceSource), "measured_csirs"), ...
    ["FDD MU design must use the directly measured CSI-RS transmit " ...
     "subspace without applying the TDD conjugate-reciprocity transform."]);
ulDesigned = sixgr.phy.mimo.designMeasuredMUMIMOPair( ...
    qCorrelatedA, qCorrelatedB, cfg, "UL", 2, 2);
assert(ulDesigned.Compatible && ...
    string(ulDesigned.ULReceiveProcessingMode) == ...
        "full_dimensional_per_re_irc" && ...
    isequal(size(ulDesigned.Member1AdmissionReceiveCombiner), [64 2]) && ...
    norm(ulDesigned.Member1AdmissionReceiveCombiner' * ...
        ulDesigned.Member1AdmissionReceiveCombiner - eye(2), "fro") <= 1e-12 && ...
    norm(ulDesigned.Member2AdmissionReceiveCombiner' * ...
        ulDesigned.Member2AdmissionReceiveCombiner - eye(2), "fro") <= 1e-12 && ...
    isequal(size(ulDesigned.Member1ReceiveCombiner), [64 64]) && ...
    isequal(ulDesigned.Member1ReceiveCombiner, eye(64)) && ...
    isequal(ulDesigned.Member2ReceiveCombiner, eye(64)) && ...
    norm(ulDesigned.Member1ReceiveCombiner' * ...
        ulDesigned.Member1ReceiveCombiner - eye(64), "fro") <= 1e-12 && ...
    norm(ulDesigned.Member2ReceiveCombiner' * ...
        ulDesigned.Member2ReceiveCombiner - eye(64), "fro") <= 1e-12 && ...
    ulDesigned.WorstLeakage_dB <= -15, ...
    "UL MU admission must use a causal measured nulling diagnostic while " + ...
    "the executable per-RE IRC path preserves all receiver branches.");
ueUL = localUEs([0 0], [10 10]);
for ulIndex = 1:numel(ueUL)
    ueUL(ulIndex).ULBufferBytes = 20000;
    ueUL(ulIndex).SRSValid = true;
    ueUL(ulIndex).SRSCausalUsable = true;
    ueUL(ulIndex).SRSCausalMeasurementId = "measured-srs-" + string(ulIndex);
    ueUL(ulIndex).LastSuccessfulSRSSlot = 1;
end
ueUL(1).MUMIMOSpatialSignature = qCorrelatedA;
ueUL(2).MUMIMOSpatialSignature = qCorrelatedB;
ueUL = localBindMeasuredSpatialSignatures(ueUL, "UL", 0);
ulScheduler = sixgr.l2.mac.SchedulerPF(cfg, "Direction", "UL");
[ulGrants, ~] = ulScheduler.schedule(0, ueUL, ...
    struct("PRBSet", 0:23, "SymbolAllocation", double(cfg.phy.pusch.symbolAllocation)));
assert(numel(ulGrants) == 2 && ...
    all(arrayfun(@(g) logical(g.MUMIMOEnabled) && ...
        isequal(size(g.MUMIMOReceiveCombiningMatrix), [64 64]) && ...
        isequal(g.MUMIMOReceiveCombiningMatrix, eye(64)) && ...
        string(g.MUMIMOReceiveProcessingMode) == ...
            "full_dimensional_per_re_irc" && ...
        string(g.MUMIMOReceiverAlgorithm) == ...
            "full_dimensional_per_re_irc" && ...
        strlength(string(g.MUMIMOAdmissionReceiveCombiningMatrixSHA256)) == 64 && ...
        isequal(size(g.MUMIMOAdmissionReceiveCombiningMatrix), [64 2]), ...
        ulGrants)), ...
    "Every scheduled UL MU grant must freeze the measured admission matrix separately from a full-dimensional IRC preprocessor.");
assert(all(arrayfun(@(g) ...
    isequal(g.PHYGrant.LegacyGrantSnapshot.MUMIMOReceiveCombiningMatrix, eye(64)) && ...
    string(g.PHYGrant.LegacyGrantSnapshot.MUMIMOReceiverAlgorithm) == ...
        "full_dimensional_per_re_irc", ulGrants)), ...
    "The immutable PHY grant must carry the exact full-dimensional UL IRC authority into receiver execution.");
ue(1).MUMIMOSpatialSignature = qCorrelatedA;
ue(2).MUMIMOSpatialSignature = ue(1).MUMIMOSpatialSignature;
ue(3).MUMIMOSpatialSignature = qCorrelatedB;
ue(4).MUMIMOSpatialSignature = ue(1).MUMIMOSpatialSignature;
ue = localBindMeasuredSpatialSignatures(ue, "DL", 0);
scheduler = sixgr.l2.mac.SchedulerPF(cfg, "Direction", "DL");
[grants, info] = scheduler.schedule(0, ue, ...
    struct("PRBSet", 0:23, "SymbolAllocation", [2 12]));
assert(numel(grants) == 2, ...
    "The configured two-user MU opportunity must emit exactly two grants.");
assert(isequal(sort(double([grants.RNTI])), [1 3]), ...
    "MU pairing must search the complete PF candidate set for a compatible measured-PMI peer.");
assert(all(double([grants.MUMIMOGroupSize]) == 2) && ...
    numel(unique(double([grants.MUMIMOGroupId]))) == 1 && ...
    all(string({grants.MUMIMOPairingStatus}) == ...
    "paired_shared_prb_spatial_multiplexing"), ...
    "Both grants must carry one exact shared-PRB MU group identity.");
assert(isequal(double(grants(1).PRBSet(:)), double(grants(2).PRBSet(:))) && ...
    isequal(double(grants(1).SymbolAllocation(:)), ...
    double(grants(2).SymbolAllocation(:))), ...
    "MU grants must occupy identical PRB and symbol resources.");
allDMRSPorts = [double(grants(1).DMRSPortSet(:).'), ...
    double(grants(2).DMRSPortSet(:).')];
assert(numel(unique(allDMRSPorts)) == 4 && ...
    numel(grants(1).DMRSPortSet) == 2 && numel(grants(2).DMRSPortSet) == 2, ...
    "Two rank-2 MU users must receive four disjoint logical DM-RS ports.");
frozen = arrayfun(@(g) logical(g.PHYGrant.IsFrozen) && ...
    strlength(string(g.PHYGrant.PrecodingState.SelectedMatrixSHA256)) > 0, grants);
assert(all(frozen), ...
    "Every MU member must be frozen independently after group finalization.");
assert(all(arrayfun(@(g) g.PHYGrant.AntennaArchitecture.NumLogicalPorts == nRF && ...
    isequal(size(g.PHYGrant.PrecodingState.MatrixLogicalPorts), [nRF 2]) && ...
    isequal(size(g.PHYGrant.PrecodingState.MatrixPhysicalPorts), [64 2]), grants)), ...
    "Two rank-2 DL members must freeze distinct 32-port baseband and 64-element physical precoders.");
assert(all(arrayfun(@(g) ...
    abs(norm(g.PHYGrant.PrecodingState.MatrixPhysicalPorts, "fro")^2 - 1) <= 1e-12 && ...
    abs(norm(g.PHYGrant.PrecodingState.Matrix, "fro")^2 - 1) <= 1e-12, grants)), ...
    "Every frozen rank-2 DL MU grant must satisfy the unit-total-power precoder contract before replay.");
