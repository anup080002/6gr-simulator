    "CQIProvenance", "measured_srs_receiver_channel_estimate", ...
    "OuterLoopEnabled", false);
amcGrant = sixgr.truth.CoupledTruthRuntime. ...
    applyMeasuredFeedbackAMCToGrantRuntime( ...
    grants(1), feedback, scheduler, cfg, "DL");
assert(logical(amcGrant.Valid) && logical(amcGrant.ExactPHYFeasible), ...
    "Measured-feedback AMC must leave the finalized MU grant executable.");
assert(double(amcGrant.MCSIndex) == 1 && ...
    string(amcGrant.MCSIndexAuthority) == ...
    "yaml_mu_mimo_first_data_mcs_until_data_feedback" && ...
    isfinite(double(amcGrant.RawCQIDerivedMCS)) && ...
    double(amcGrant.RawCQIDerivedMCS) >= double(amcGrant.MCSIndex) && ...
    double(amcGrant.NumLayers) == 2, ...
    "A first shared-PRB MU data grant driven only by SRS must retain the " + ...
    "raw measured CQI evidence and rank-2 spatial authority while using " + ...
    "the YAML-owned conservative first-data MCS.");
dataFeedback = feedback;
dataFeedback.FeedbackSourceSignal = "DL_CSI_REPORT";
dataFeedback.FeedbackCRCPass = true;
dataFeedback.HasSharedMUMIMODataFeedback = true;
dataFeedback.MCSSelectionSource = "runtime_link_adaptation_decision";
dataAdaptedGrant = sixgr.truth.CoupledTruthRuntime. ...
    applyMeasuredFeedbackAMCToGrantRuntime( ...
    grants(1), dataFeedback, scheduler, cfg, "DL");
assert(double(dataAdaptedGrant.MCSIndex) == 10 && ...
    string(dataAdaptedGrant.MCSIndexAuthority) == ...
    "runtime_link_adaptation_decision", ...
    "Actual data-channel feedback must immediately supersede first-data bootstrap authority.");
pilotFeedback = dataFeedback;
pilotFeedback.FeedbackCRCPass = NaN;
pilotFeedback.HasDataFeedback = true;
pilotFeedback.LastDataFeedbackSlot = 7;
pilotFeedback.LastDataFeedbackCRCPass = true;
pilotAdaptedGrant = sixgr.truth.CoupledTruthRuntime. ...
    applyMeasuredFeedbackAMCToGrantRuntime( ...
    grants(1), pilotFeedback, scheduler, cfg, "DL");
assert(double(pilotAdaptedGrant.MCSIndex) == 10 && ...
    string(pilotAdaptedGrant.MCSIndexAuthority) == ...
    "runtime_link_adaptation_decision", ...
    ["A newer pilot report must not erase the persistent fact that genuine " ...
     "shared-data receiver feedback has already completed."]);
initialPilotFeedback = feedback;
initialPilotFeedback.FeedbackCRCPass = NaN;
initialPilotFeedback.HasDataFeedback = false;
initialPilotFeedback.HasSharedMUMIMODataFeedback = false;
initialPilotGrant = sixgr.truth.CoupledTruthRuntime. ...
    applyMeasuredFeedbackAMCToGrantRuntime( ...
    grants(1), initialPilotFeedback, scheduler, cfg, "DL");
assert(double(initialPilotGrant.MCSIndex) == 1 && ...
    string(initialPilotGrant.MCSIndexAuthority) == ...
    "yaml_mu_mimo_first_data_mcs_until_data_feedback", ...
    ["A pilot-only DL CSI-RS report without any earlier data feedback must " ...
     "retain the YAML-owned first-data bootstrap."]);
assert(abs(norm(amcGrant.PHYGrant.PrecodingState.MatrixPhysicalPorts, "fro")^2 - 1) <= 1e-12 && ...
    isequal(double(amcGrant.PHYGrant.PrecodingState.MatrixPhysicalPorts), ...
        double(grants(1).PHYGrant.PrecodingState.MatrixPhysicalPorts)) && ...
    isequal(double(amcGrant.PHYGrant.PrecodingState.MatrixLogicalPorts), ...
        double(grants(1).PHYGrant.PrecodingState.MatrixLogicalPorts)) && ...
    isequal(double(amcGrant.PHYGrant.PrecodingState.HybridElementToPortMatrix), ...
        double(grants(1).PHYGrant.PrecodingState.HybridElementToPortMatrix)) && ...
    string(amcGrant.PHYGrant.PrecodingState.SelectedMatrixSHA256) == ...
        string(grants(1).PHYGrant.PrecodingState.SelectedMatrixSHA256), ...
    "Post-scheduler AMC refreeze must preserve the exact frozen measured-MU spatial contract.");
p1 = double(grants(1).PHYGrant.PrecodingState.MatrixPhysicalPorts);
p2 = double(grants(2).PHYGrant.PrecodingState.MatrixPhysicalPorts);
leakage1 = norm(ue(1).MUMIMOSpatialSignature.' * p2, "fro")^2 ./ ...
    max(norm(ue(1).MUMIMOSpatialSignature.' * p1, "fro")^2, realmin);
leakage2 = norm(ue(3).MUMIMOSpatialSignature.' * p1, "fro")^2 ./ ...
    max(norm(ue(3).MUMIMOSpatialSignature.' * p2, "fro")^2, realmin);
requiredLeakage = 10.^(double(grants(1).MUMIMORequiredLeakageThreshold_dB) ./ 10);
assert(leakage1 <= requiredLeakage && leakage2 <= requiredLeakage, ...
    ["Frozen physical DL MU precoders must satisfy each victim's configured " ...
     "other-user-beam/own-desired-beam leakage ratio without requiring an unnecessarily " ...
     "destructive exact zero-forcing solution."]);
assert(all(string({grants.MUMIMOHybridRFDesignPolicy}) == ...
    "fixed_configured_matrix") && ...
    all(string(arrayfun(@(g) g.PHYGrant.PrecodingState.HybridRFDesignPolicy, ...
    grants, "UniformOutput", false)) == ...
    "fixed_configured_matrix"), ...
    "Scheduler and frozen PHY grants must bind the config-selected hybrid RF design policy.");
projectedMUConfig = sixgr.phy.grant.applyPHYGrantToConfig(cfg, grants(1).PHYGrant);
projectedMUConfig = sixgr.phy.grid.applyRuntimeCarrierTimeline( ...
