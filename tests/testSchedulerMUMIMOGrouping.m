    "Candidate-decision truth must expose the exact peer, leakage and measured-SRS evidence that admitted the MU pair.");
assert(all(double([grants.MUMIMOPairingMetricValue_dB]) <= ...
        double([grants.MUMIMORequiredLeakageThreshold_dB])) && ...
    all(string({grants.MUMIMOPairingEvidenceSource}) == ...
    "causal_measured_srs_complete_peer_subspace_reciprocity_phase_only_hybrid_and_frozen_baseband") && ...
    all(strlength(string({grants.MUMIMOSpatialFilterMatrixSHA256})) == 64), ...
    "MU grants must retain the measured executable spatial-filter evidence.");
assert(all(string({grants.MUMIMOSpatialDesignEvidenceSource}) == ...
    string({grants.MUMIMOPairingEvidenceSource})) && ...
    all(strlength(string({grants.HybridElementToPortMatrixSHA256})) == 64) && ...
    all(strlength(string({grants.BaseHybridElementToPortMatrixSHA256})) == 64), ...
    "Frozen filter authority and current MU pairing evidence must be independently digest-bound.");

% Receiver completion must not erase the exact frozen MU contract when the
% raw waveform trial is streamed. Conversely, MU annotation must not alter
% receiver-derived measurements.
trialT = table([12.5; 13.0], [true; false], ...
    'VariableNames', {'PostEqSINR_dB','CRCPass'});
annotatedT = sixgr.truth.annotateFrozenMUMIMOTrialEvidence(trialT, grants(1));
assert(isequal(annotatedT.PostEqSINR_dB, trialT.PostEqSINR_dB) && ...
    isequal(annotatedT.CRCPass, trialT.CRCPass), ...
    "Frozen MU evidence annotation must not overwrite receiver measurements.");
assert(all(annotatedT.MUMIMOEnabled) && ...
    all(annotatedT.MUMIMOGroupSize == grants(1).MUMIMOGroupSize) && ...
    all(annotatedT.MUMIMOGroupId == grants(1).MUMIMOGroupId) && ...
    all(annotatedT.MUMIMOPairingStatus == string(grants(1).MUMIMOPairingStatus)) && ...
    all(annotatedT.MUMIMOPairingMetricSource == string(grants(1).MUMIMOPairingMetricSource)) && ...
    all(annotatedT.MUMIMOPairingMetricValue_dB == grants(1).MUMIMOPairingMetricValue_dB) && ...
    all(annotatedT.MUMIMOPairingEvidenceSource == string(grants(1).MUMIMOPairingEvidenceSource)) && ...
    all(annotatedT.MUMIMOSpatialDesignEvidenceSource == string(grants(1).MUMIMOSpatialDesignEvidenceSource)) && ...
    all(annotatedT.HybridElementToPortMatrixSHA256 == string(grants(1).HybridElementToPortMatrixSHA256)) && ...
    all(annotatedT.PRBStart == min(grants(1).PRBSet)) && ...
    all(annotatedT.PRBCount == numel(unique(grants(1).PRBSet))) && ...
    all(annotatedT.SymbolStart == grants(1).SymbolAllocation(1)) && ...
    all(annotatedT.NumSymbols == grants(1).SymbolAllocation(2)), ...
    "Raw trials must preserve every exact MU pairing field from the frozen grant.");

% A different configured PMI without measured CQI is not causal MU
% evidence.  Bootstrap rows remain orthogonal SU grants rather than being
% forced into an MU label.
bootstrapUE = localUEs([0 1 2 3], [1 1 1 1]);
for bootstrapIndex = 1:numel(bootstrapUE)
    % CQI 0 is an explicit out-of-range report, not missing feedback.  A
    % bootstrap scheduling test must instead carry a positive conservative
    % CQI with explicit non-measured provenance and authorization.
    bootstrapUE(bootstrapIndex).FeedbackValid = false;
    bootstrapUE(bootstrapIndex).BootstrapCQIUsableForScheduling = true;
    bootstrapUE(bootstrapIndex).BootstrapCQISource = ...
        "yaml_enabled_conservative_bootstrap_not_measured_cqi";
end
bootstrapScheduler = sixgr.l2.mac.SchedulerPF(cfg, "Direction", "DL");
bootstrapGrants = bootstrapScheduler.schedule(0, bootstrapUE, ...
    struct("PRBSet", 0:23, "SymbolAllocation", [2 12]));
assert(numel(bootstrapGrants) == 2 && ...
    all(double([bootstrapGrants.MUMIMOGroupSize]) == 1) && ...
    ~isequal(double(bootstrapGrants(1).PRBSet(:)), ...
    double(bootstrapGrants(2).PRBSet(:))), ...
    "Unmeasured bootstrap CQI must not be upgraded to shared-PRB MU execution.");
assert(all(arrayfun(@(g) ...
    abs(norm(g.PHYGrant.PrecodingState.MatrixPhysicalPorts, "fro")^2 - 1) <= 1e-12 && ...
    abs(norm(g.PHYGrant.PrecodingState.MatrixLogicalPorts, "fro")^2 - 1) <= 1e-12, ...
    bootstrapGrants)), ...
    "Rank-2 SU fallback grants must split the configured total power equally across layers.");

% Even valid CQI and different PMI values are insufficient without a
% measured spatial matrix.  This guards against restoring the former
% PMI-inequality proxy.
pmiOnlyUE = localUEs([0 1 2 3], [10 10 10 10]);
retxHARQ = sixgr.l2.mac.HARQEntity(cfg, "Direction", "DL", ...
    "NumProcesses", 4, "MaxRetx", 3);
pmiOnlyScheduler = sixgr.l2.mac.SchedulerPF(cfg, "Direction", "DL", ...
    "HARQ", retxHARQ);
pmiOnlyGrants = pmiOnlyScheduler.schedule(0, pmiOnlyUE, ...
    struct("PRBSet", 0:23, "SymbolAllocation", [2 12]));
assert(numel(pmiOnlyGrants) == 2 && ...
    all(double([pmiOnlyGrants.MUMIMOGroupSize]) == 1), ...
    "Different PMI indices without measured matrices must remain SU scheduling.");

% A numeric matrix is also insufficient when its provenance is configured,
% stale, or digest-invalid. This prevents executable/frozen beam matrices
% from being recycled as measured scheduler CSI.
invalidSourceUE = ue(1:2);
invalidSourceUE(1).MUMIMOSpatialSignatureSource = "executed_frozen_phy_grant_precoding_matrix";
invalidSourceUE(2).MUMIMOSpatialSignatureAgeSlots = cfg.phy.mimo.measurementMaxAgeSlots + 1;
invalidSourceScheduler = sixgr.l2.mac.SchedulerPF(cfg, "Direction", "DL");
[invalidSourceGrants, invalidSourceInfo] = invalidSourceScheduler.schedule(0, invalidSourceUE, ...
    struct("PRBSet", 0:23, "SymbolAllocation", [2 12]));
assert(~isempty(invalidSourceGrants) && ...
    all(~logical([invalidSourceGrants.MUMIMOEnabled])) && ...
    ~any(double([invalidSourceGrants.MUMIMOGroupSize]) > 1), ...
    "Non-SRS or stale spatial matrices must not authorize shared-PRB MU execution.");
invalidDecision = invalidSourceInfo.CandidateTable;
assert(any(invalidDecision.MUMIMOAdmissionEvaluated) && ...
    ~any(invalidDecision.MUMIMOAdmissionCompatible) && ...
    all(strlength(string(invalidDecision.MUMIMOAdmissionEvidenceSource( ...
        invalidDecision.MUMIMOAdmissionEvaluated))) > 0), ...
    "Rejected MU admission must retain the exact causal-provenance or age failure instead of appearing unevaluated.");

% Once causal SRS becomes available, two pending rank-2 retransmissions
% with the same allocation shape may share one opportunity. The TB, NDI,
% RV lineage, rank, and TBS stay immutable while a fresh measured spatial
% filter is frozen for the retransmission opportunity.
for grantIndex = 1:2
    original = pmiOnlyGrants(grantIndex);
    harqId = double(original.HARQ.HarqID);
    original.HARQTBContext = struct( ...
        "OriginalNumLayers", double(original.NumLayers), ...
        "TBSBits", double(original.TBSBits), ...
        "HARQProcessId", harqId, ...
        "NDI", logical(original.HARQ.NDI), ...
        "NDIEpoch", double(sixgr.util.structGet(original.HARQ, "NDIEpoch", 1)));
    payload = zeros(round(double(original.TBSBits)), 1, "uint8");
    pmiOnlyScheduler.HARQ.onTx(double(original.RNTI), harqId, ...
        payload, original, 0);
    pmiOnlyScheduler.HARQ.onFeedback(double(original.RNTI), harqId, ...
        "NACK", "SourceSlot", 0, "FeedbackSlot", 4);
end
retxUE = localUEs([0 1 2 3], [10 10 10 10]);
retxUE(1).MUMIMOSpatialSignature = F(:, 1:2);
retxUE(2).MUMIMOSpatialSignature = F(:, 3:4);
retxUE = localBindMeasuredSpatialSignatures(retxUE, "DL", 5);
retxGrants = pmiOnlyScheduler.schedule(5, retxUE, ...
    struct("PRBSet", 0:23, "SymbolAllocation", [2 12]));
assert(numel(retxGrants) == 2 && ...
    all(string({retxGrants.GrantReason}) == "harq_retx_mu_mimo") && ...
    all(logical([retxGrants.IsRetransmission])) && ...
    all(double([retxGrants.MUMIMOGroupSize]) == 2) && ...
    isequal(double(retxGrants(1).PRBSet(:)), double(retxGrants(2).PRBSet(:))), ...
    "Compatible pending HARQ TBs must execute as one measured shared-PRB MU retransmission group.");
for grantIndex = 1:2
    original = pmiOnlyGrants(grantIndex);
    replay = retxGrants([retxGrants.RNTI] == original.RNTI);
    assert(numel(replay) == 1 && replay.TBSBits == original.TBSBits && ...
        replay.NumLayers == original.NumLayers && replay.HARQ.NDI == original.HARQ.NDI && ...
        replay.HARQ.RV ~= original.HARQ.RV && ...
        replay.PHYGrant.HARQProcessKey.IsRetransmission, ...
        "MU retransmission grouping must preserve the original TB spatial/rate contract and advance only HARQ RV.");
end

% If only one member of an earlier MU group is pending, replay its frozen
% beam but clear all current shared-resource labels. Historical group
% identity is retained only in explicit Prior* fields.
singleRetxHARQ = sixgr.l2.mac.HARQEntity(cfg, "Direction", "DL", ...
    "NumProcesses", 4, "MaxRetx", 3);
singleRetxScheduler = sixgr.l2.mac.SchedulerPF(staleSingleUserCfg, "Direction", "DL", ...
    "HARQ", singleRetxHARQ);
[singleOriginal, ~] = singleRetxScheduler.schedule(0, ue([1 3]), ...
    struct("PRBSet", 0:23, "SymbolAllocation", [2 12]));
assert(numel(singleOriginal) == 2 && all([singleOriginal.MUMIMOEnabled]));
original = singleOriginal(1);
harqId = double(original.HARQ.HarqID);
original.HARQTBContext = struct( ...
    "OriginalNumLayers", double(original.NumLayers), ...
    "TBSBits", double(original.TBSBits), ...
    "HARQProcessId", harqId, "NDI", logical(original.HARQ.NDI), ...
    "NDIEpoch", double(sixgr.util.structGet(original.HARQ, "NDIEpoch", 1)));
singleRetxScheduler.HARQ.onTx(double(original.RNTI), harqId, ...
    zeros(round(double(original.TBSBits)), 1, "uint8"), original, 0);
singleRetxScheduler.HARQ.onFeedback(double(original.RNTI), harqId, ...
    "NACK", "SourceSlot", 0, "FeedbackSlot", 4);
singleRetxUE = ue([1 3]);
singleRetxUE(2).DLBufferBytes = 0;
