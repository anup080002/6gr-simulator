function ok = testSameExecutionRuntimeArtifactCatalog()
%TESTSAMEEXECUTIONRUNTIMEARTIFACTCATALOG Preserve run/phase evidence scope.
%
% A single scenario execution may publish only artifacts registered from
% that exact runtime.  It must not inherit the much larger statistical
% phase-pack contract or weaken the phase-pack minima in memory.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
root = sixgr.artifact.ContractCatalog.repositoryRoot();
phaseCatalog = sixgr.artifact.ContractCatalog.load(root, "phase_pack");
runtimeCatalog = sixgr.artifact.ContractCatalog.load(root, "runtime_in_path");

assert(height(phaseCatalog) == 1350, ...
    "The immutable phase-pack catalog must retain all 1,350 contracts.");
assert(height(runtimeCatalog) == 3 && ...
    nnz(runtimeCatalog.ArtifactType == "CSV") == 3 && ...
    ~any(runtimeCatalog.ArtifactType == "PNG"), ...
    ["One run must expose exactly three in-path CSV contracts; " ...
    "post-run CSV materialization owns every raster."]);

expected = table( ...
    ["initial_access";"pdsch";"pusch"], ...
    ["CSV";"CSV";"CSV"], ...
    ["prach_detection_trials.csv"; ...
     "pdsch_bler_curve.csv"; ...
     "pusch_bler_curve.csv"], ...
    'VariableNames', {'Domain','ArtifactType','FileName'});
observed = sortrows(runtimeCatalog(:, expected.Properties.VariableNames), ...
    expected.Properties.VariableNames);
expected = sortrows(expected, expected.Properties.VariableNames);
assert(isequal(observed, expected), ...
    "The same-execution contract set drifted or absorbed phase-only evidence.");

assert(all(runtimeCatalog.Profile == "base") && ...
    all(runtimeCatalog.Required) && ...
    all(endsWith(runtimeCatalog.ContractID, "|runtime_in_path")), ...
    "Runtime contracts require an explicit base/in-path identity.");
assert(all(runtimeCatalog.MinimumRows == 1), ...
    "A same-execution artifact must contain at least one genuine runtime observation.");
runtimePaths = replace(runtimeCatalog.OutputRelativePath, "\", "/");
assert(all(arrayfun(@(k) startsWith(runtimePaths(k), ...
    runtimeCatalog.Component(k) + "/"), (1:height(runtimeCatalog)).')), ...
    "Runtime outputs must remain inside canonical component folders.");

% The derived runtime view must not mutate or replace the phase-pack
% statistical requirement from which it was selected.
phasePrach = phaseCatalog.Domain == "initial_access" & ...
    phaseCatalog.Profile == "base" & ...
    phaseCatalog.ArtifactType == "CSV" & ...
    phaseCatalog.FileName == "prach_detection_trials.csv";
runtimePrach = runtimeCatalog.Domain == "initial_access" & ...
    runtimeCatalog.ArtifactType == "CSV";
assert(nnz(phasePrach) == 1 && phaseCatalog.MinimumRows(phasePrach) == 100, ...
    "The independent PRACH phase qualification must still require 100 trials.");
assert(nnz(runtimePrach) == 1 && runtimeCatalog.MinimumRows(runtimePrach) == 1, ...
    "The one-run PRACH contract must remain a separately identified observation contract.");
assert(runtimeCatalog.SourceContract(runtimePrach) == ...
    phaseCatalog.SourceContract(phasePrach), ...
    "Runtime and phase views must retain traceability to the same source contract.");

ok = true;
end
