function ok = testH4100RFImpairmentRuntime()
%TESTH4100RFIMPAIRMENTRUNTIME Qualify the exact enabled H4 RF profiles.

setup6GRSimToolkit("Verbose", false);
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    "simulator", "configs", "scenarios", ...
    "h4_100_cdlc100_connected_impaired_40db_gate.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scenario, ...
    fullfile(tempdir, "h4_100_rf_impairment_runtime"));
carrier = sixgr.phy.grid.makeCarrier(cfg);
ofdmInfo = nrOFDMInfo(carrier);
sampleRate = double(ofdmInfo.SampleRate);
assert(abs(sampleRate - 122.88e6) < 1, ...
    "The H4 100 MHz mu-1 waveform must use the resolved 122.88 MSa/s clock.");
assert(logical(sixgr.util.structGet(cfg, "phy.sync.fineCFOEnabled", false)) && ...
    string(sixgr.util.structGet(cfg, "phy.sync.fineCFOMethod", "")) == "cyclic_prefix", ...
    "The enabled 400 Hz impairment must activate the received-SSB CP CFO estimator.");

phaseNoise = sixgr.rf.PhaseNoiseModel(cfg, sampleRate, 20260927);
assert(phaseNoise.Enable && ...
    phaseNoise.Backend == "sixgr_rf_runtime_phase_noise_process" && ...
    phaseNoise.TruthClassification == "runtime_calibrated_mask_model" && ...
    strlength(phaseNoise.ApproximationReason) == 0, ...
    "The H4 phase-noise stage must use its explicit versioned runtime mask.");
[paProfile, paCanonical] = sixgr.rf.runtime.PAProfile.fromConfiguration(cfg);
assert(paCanonical && lower(string(paProfile.Model)) == "rapp" && ...
    string(paProfile.ReferenceDomain)=="normalized_complex_baseband_full_scale" && ...
    double(paProfile.InputBackoff_dB) == 8, ...
    "The H4 PA must resolve to the explicit bounded RAPP study profile.");

epoch = double(sixgr.util.structGet(cfg, "rf.configurationEpoch", NaN));
r = RandStream("Threefry", "Seed", 20260928);
txInput = 0.1 .* complex(randn(r,256,64),randn(r,256,64));
tx = sixgr.rf.runtime.RFImpairmentStream( ...
    cfg,"tx","DL",sampleRate,64,0,epoch,true);
txOut = tx.apply(sixgr.phy.waveform.WaveformChunk(txInput,0),epoch);
assert(all(isfinite(txOut.Waveform),"all") && ...
    contains(string(txOut.Replay.RFStageOrder),"tx_dac") && ...
    txOut.Replay.DACQuantizationApplied && txOut.Replay.PAApplied && ...
    txOut.Replay.PhaseNoiseApplied && txOut.Replay.TimingOffsetApplied, ...
    "The retained H4 TX stream must execute DAC, PA, phase noise and timing.");

rxInput = 0.1 .* complex(randn(r,256,4),randn(r,256,4));
rx = sixgr.rf.runtime.RFImpairmentStream( ...
    cfg,"rx","DL",sampleRate,4,0,epoch,true);
rxOut = rx.apply(sixgr.phy.waveform.WaveformChunk(rxInput,0),epoch);
assert(all(isfinite(rxOut.Waveform),"all") && ...
    rxOut.Replay.ADCQuantizationApplied && ...
    rxOut.Replay.PhaseNoiseApplied && rxOut.Replay.TimingOffsetApplied, ...
    "The retained H4 RX stream must execute phase noise, timing and ADC.");

ok = true;
disp("H4_100_RF_IMPAIRMENT_RUNTIME_PASS");
end
