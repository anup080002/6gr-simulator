function ok=testRuntimeHARQMeasuredLatency()
% Clock/identity algebra only; physical receiver tests establish integration.
cfg.phy.carrier.SubcarrierSpacing_kHz=15;
root=tempname; mkdir(root); clean=onCleanup(@()rmdir(root,'s')); %#ok<NASGU>
T=table(["DL";"DL"],ones(2,1),ones(2,1),[0;1],[1;2],ones(2,1), ...
    ["a";"b"],["grant-a";"grant-b"],true(2,1),true(2,1),false(2,1),[3;4], ...
    [100;1100],[500;1500],repmat(1e6,2,1), ...
    repmat("executed_prepared_waveform_origin_and_OFDM_symbol_lengths",2,1), ...
    'VariableNames',{'Direction','UEIndex','RNTI','HarqID','Slot','SweepPointIndex', ...
    'TBId','PHYGrantContextId','CurrentDecodeOK','CombinedDecodeOK','IsRetransmission', ...
    'FeedbackDueSlot','DataTransmitSymbolStartSample','DataTransmitSymbolEndSampleExclusive', ...
    'DataTransmitSampleRateHz','DataTransmitTimingSource'});
F=table(ones(2,1),["grant-a";"grant-b"],ones(2,1),ones(2,1),[1;2],[0;1], ...
    ["DL";"DL"],["ACK";"DTX"],[true;false],[true;false],["rx-a";"rx-b"], ...
    ["PUCCH";"PUSCH"],true(2,1),false(2,1),ones(2,1),[2800;4800],[2700;4700], ...
    repmat(1e6,2,1),'VariableNames',{'SweepPointIndex','PHYGrantContextId','UEIndex','RNTI', ...
    'SourceSlot','HarqID','FeedbackForDirection','FeedbackOutcome','ObservedAck','ReceiverUsable', ...
    'ObservationID','UCITransport','HARQFeedbackApplied','StaleFeedbackIgnored','BitIndex', ...
    'AvailableAtSample','ObservationEndSampleExclusive','ObservationSampleRateHz'});
publish=@(a,b)sixgr.truth.publishRuntimeHARQDiagnostics(cfg,fullfile(root,'air_interface'), ...
    struct('TimelineTable',a,'FeedbackObservationTable',b));
out=publish(T,F); P=out.PacketTable;
assert(all(P.ScheduledFeedbackOffset_ms==2) && abs(P.RTT_ms(1)-2.7)<1e-12 && isnan(P.RTT_ms(2)));
assert(max(abs(P.FeedbackDispositionLatency_ms-[2.7;3.7]))<1e-12);
assert(contains(P.RTTStatus(2),'DTX') && P.RTT_slots(1)==P.RTT_ms(1));
saved=readtable(out.PacketCSV,'TextType','string');
assert(isequaln(saved.RTT_ms,P.RTT_ms) && isequal(saved.ScheduledFeedbackOffset_ms,P.ScheduledFeedbackOffset_ms));
late=F; late.AvailableAtSample(1)=3300; next=publish(T,late);
assert(abs(next.PacketTable.RTT_ms(1)-3.2)<1e-12 && next.PacketTable.ScheduledFeedbackOffset_ms(1)==2);
none=publish(T,table()); assert(all(isnan(none.PacketTable.RTT_ms)));
missing=T; missing.DataTransmitSymbolStartSample(:)=NaN; none=publish(missing,F);
assert(all(isnan(none.PacketTable.RTT_ms)),'Never reconstruct transmitted symbols from Slot.');
bad=F; bad.ObservationSampleRateHz(1)=2e6;
reject(@()publish(T,bad),'sixgr:truth:HARQRoundTripClockMismatch');
bad=F; bad.AvailableAtSample(1)=400; bad.ObservationEndSampleExclusive(1)=350;
reject(@()publish(T,bad),'sixgr:truth:HARQRoundTripClockMismatch');
fprintf('RUNTIME_HARQ_MEASURED_LATENCY_PASS scheduled=2ms observed=2.7ms DTX_RTT=unavailable\n');
ok=true;
end

function reject(f,id)
try, f(); catch ex, assert(strcmp(ex.identifier,id),'%s',ex.message); return; end
error('test:ExpectedRejection','Expected %s',id);
end
