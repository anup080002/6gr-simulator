function localAssertOrder(chainStruct, expectedIds, chainName)
assert(isfield(chainStruct, "ordered_blocks") && isstruct(chainStruct.ordered_blocks), ...
    "sixgr:test:6GProcessingChains:MissingBlocks", ...
    "processing_chains.%s must contain ordered_blocks.", chainName);
assert(logical(chainStruct.exact_order_locked), ...
    "sixgr:test:6GProcessingChains:UnlockedOrder", ...
    "processing_chains.%s must lock the exact block order.", chainName);

blocks = chainStruct.ordered_blocks;
orders = [blocks.order];
ids = string({blocks.block_id});

assert(isequal(orders, 1:numel(blocks)), ...
    "sixgr:test:6GProcessingChains:BadOrderIndices", ...
    "processing_chains.%s must use contiguous order indices.", chainName);
assert(isequal(ids, expectedIds), ...
    "sixgr:test:6GProcessingChains:UnexpectedBlockOrder", ...
    "processing_chains.%s has an unexpected block order.", chainName);

for i = 1:numel(blocks)
    cfgPaths = string(blocks(i).config_paths);
    assert(~isempty(cfgPaths) && all(strlength(cfgPaths) > 0), ...
        "sixgr:test:6GProcessingChains:MissingConfigBinding", ...
        "processing_chains.%s block %s must bind to at least one config path.", chainName, ids(i));
end
end
