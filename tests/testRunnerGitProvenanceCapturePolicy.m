function ok = testRunnerGitProvenanceCapturePolicy()
%TESTRUNNERGITPROVENANCECAPTUREPOLICY Guard bounded, honest provenance capture.

setup6GRSimToolkit("Verbose", false);
runnerPath = fullfile(fileparts(fileparts(mfilename("fullpath"))), ...
    "+sixgr", "+lls6g", "+runners", "runSingle.m");
source = string(fileread(runnerPath));

captureAssignments = count(source, ...
    "sourceProvenance = localDetectGitProvenance(");
assert(captureAssignments == 1, ...
    "Runner must capture dirty-tree provenance exactly once per process.");
assert(contains(source, ...
    "scenarioStatus, sourceProvenance)"), ...
    "Every manifest rewrite must reuse the process-level provenance snapshot.");
assert(contains(source, "SIXGR_EXECUTION_PATCH_BUNDLE_V2") && ...
    contains(source, "artifacts/focused_audits/") && ...
    contains(source, "artifacts/focused_logs/") && ...
    contains(source, "generated_evidence_not_source") && ...
    contains(source, "ReconstructableFromPatchBundle: false"), ...
    "Generated audit/log exclusions must remain explicit and non-reconstructable.");

ok = true;
fprintf("testRunnerGitProvenanceCapturePolicy: PASS\n");
end
