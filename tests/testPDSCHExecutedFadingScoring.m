function ok=testPDSCHExecutedFadingScoring()
% Same-execution post-decode scoring; no calibration/performance claim.
setup6GRSimToolkit('Verbose',false);
fixture=StrictPDSCHChainFixture.create(2,'NPRB',6,'FrequencySelective',true);
tx=sixgr.pdsch.PDSCHTransmitter(fixture.TransportBlocks,fixture.Assignment, ...
    fixture.ResourcePlan,fixture.Carrier,fixture.ReferenceConfig, ...
    'PrecoderBundle',fixture.PrecoderBundle);
for model=["TDL-C" "CDL-C"]
    cfg=sixgr.config.defaultConfig();
    cfg.run.strictMode=true; cfg.run.noProxyTruthContract=true;
    cfg.channel.model=char(model); cfg.channel.awgnOnly=false;
    cfg.channel.delayProfile=char(model); cfg.channel.delaySpread_s=100e-9;
    cfg.channel.doppler_Hz=30; cfg.channel.perSampleFadingEnabled=true;
    cfg.channel.runtimeElementExpansionChunkSamples=257;
    cfg.channel.nTxAnt=2; cfg.channel.nRxAnt=4;
    cfg.phy.nTxAnt=2; cfg.phy.nRxAnt=4;
    if startsWith(model,'TDL'), cfg.channel.tdlProfile=char(model);
    else, cfg.channel.cdlProfile=char(model); end
    state=sixgr.channel.ChannelFactory.createRuntimeChannelState(cfg,'DL', ...
        'Seed',6713,'LinkKey','executed_scoring_'+model);
    state=sixgr.channel.ChannelFactory.materializeRuntimeChannelState(state,cfg, ...
        tx.Waveform,struct('OFDM',tx.OFDMInfo),'NumTxAnt',2,'NumRxAnt',4);
    untouched=sixgr.channel.ChannelFactory.forkRuntimeChannelState(state);
    [plain,plainReplay,untouched]=sixgr.channel.ChannelFactory.applyRuntimeChannelState( ...
        untouched,tx.Waveform,'InputSampleDomain','materialized_channel_ports', ...
        'CapturePathGains',false);
    [waveform,replay,state,reference]=sixgr.channel.ChannelFactory.applyRuntimeChannelState( ...
        state,tx.Waveform,'InputSampleDomain','materialized_channel_ports', ...
        'CaptureChannelReference',true);
    assert(isequal(plain,waveform) && state.CurrentSampleIndex==untouched.CurrentSampleIndex && ...
        state.TotalObjectInputSamples==untouched.TotalObjectInputSamples && ...
        reference.CanonicalEndSampleExclusive==state.CurrentSampleIndex && ...
        reference.AppliedAlignmentTrimSamples==plainReplay.RuntimeChannelAppliedAlignmentTrimSamples && ...
        reference.AlignmentLookaheadSamples==replay.RuntimeChannelAlignmentLookaheadSamples, ...
        'Scoring capture must not change the waveform, alignment, or canonical fading clock.');
    following=tx.Waveform(1:117,:);
    [a,ra,after]=sixgr.channel.ChannelFactory.applyRuntimeChannelState(state,following, ...
        'InputSampleDomain','materialized_channel_ports');
    [b,rb,plainAfter]=sixgr.channel.ChannelFactory.applyRuntimeChannelState(untouched,following, ...
        'InputSampleDomain','materialized_channel_ports');
    fprintf('SCORING_NEXT_WAVEFORM model=%s relative_error=%.17g clock_delta=%g object_clock_delta=%g capture_a=%d capture_b=%d\n', ...
        model,norm(a-b,'fro')/max(norm(b,'fro'),realmin), ...
        after.CurrentSampleIndex-plainAfter.CurrentSampleIndex, ...
        after.TotalObjectInputSamples-plainAfter.TotalObjectInputSamples, ...
        ra.RuntimeChannelPathGainCaptureRequested,rb.RuntimeChannelPathGainCaptureRequested);
    assert(isequal(a,b) && after.CurrentSampleIndex==plainAfter.CurrentSampleIndex, ...
        'Reference-tail capture must not consume future canonical channel samples.');
    receiver=rmfield(fixture.ReceiverConfig,'ReferenceChannelGain');
    receiver.ChannelModel=char(model); receiver.NPhysicalRxAntennas=4;
    rx=sixgr.pdsch.PDSCHReceiver(waveform,fixture.Assignment,fixture.ResourcePlan, ...
        fixture.Carrier,fixture.ReferenceConfig,receiver,'CodingPlans',tx.CodingPlans);
    before=rx;
    [score,truth,estimate]=sixgr.pdsch.scoreExecutedFadingChannel(tx,rx,reference);
    assert(isequaln(before,rx) && isnan(rx.Metrics.ChannelEstimateNMSE) && ...
        isfinite(score.NMSE_dB) && ~score.ReceiverEstimatorInput && ...
        ~score.GainOrPhaseFitted && score.AdditionalChannelExecutions==0 && ...
        abs(score.NMSE-sum(abs(estimate-truth).^2,'all')/sum(abs(truth).^2,'all'))<1e-14, ...
        'Scoring must retain the complete energy ratio without modifying receiver evidence.');
    % Negative estimator control: an incorrect gain must remain an error,
    % not disappear through a fitted amplitude/phase or normalization step.
    changed=rx; changed.EffectiveLayerChannelEstimate=2*rx.EffectiveLayerChannelEstimate;
    corrupted=sixgr.pdsch.scoreExecutedFadingChannel(tx,changed,reference);
    assert(corrupted.NMSE>score.NMSE+.1,'Estimator gain error must remain measurable.');
    wrong=tx; wrong.Waveform(1,1)=wrong.Waveform(1,1)+1;
    expectError(@()sixgr.pdsch.scoreExecutedFadingChannel(wrong,rx,reference), ...
        'sixgr:pdsch:ExecutedScoringCaptureMismatch');
    short=reference; short.PathGains=short.PathGains(1:10,:,:,:);
    expectError(@()sixgr.pdsch.scoreExecutedFadingChannel(tx,rx,short), ...
        'sixgr:pdsch:ExecutedScoringCaptureMismatch');
    bad=reference; bad.ReceiverEstimatorInput=true;
    expectError(@()sixgr.pdsch.scoreExecutedFadingChannel(tx,rx,bad), ...
        'sixgr:pdsch:InvalidExecutedScoringReference');
    fprintf('EXECUTED_FADING_SCORING %s NMSE=%g values=%d unchanged_waveform=1\n', ...
        model,score.NMSE_dB,score.ComparedValues);
end
ok=true;
end

function expectError(call,identifier)
try
    call();
catch err
    assert(strcmp(err.identifier,identifier),'Unexpected failure: %s',err.identifier);
    return;
end
error('test:MissingFailure','Expected %s.',identifier);
end
