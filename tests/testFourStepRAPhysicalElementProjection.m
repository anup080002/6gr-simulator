function ok = testFourStepRAPhysicalElementProjection()
%TESTFOURSTEPRAPHYSICALELEMENTPROJECTION Guard Msg1 logical-to-physical coupling.

scenarioPath = fullfile("simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
runRoot = tempname;
mkdir(runRoot);
cleanup = onCleanup(@() localCleanup(runRoot)); %#ok<NASGU>
cfg = sixgr.config.normalizeConfig( ...
    sixgr.lls6g.buildInternalConfig(scfg, runRoot));

multiUser = struct("Enabled", true, "NumUsers", 1, "RNTIStart", 1, ...
    "ExecutionModel", "slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfg, runRoot, multiUser, struct(), 1);
state.CurrentSlot = 2;
state.CurrentServingIdx(:) = 1;
[cfgRuntime, ~] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
    cfg, state, 1, "UL");

% Stop after the real Msg1 propagation stage.  The injected detector miss is
% deliberate; it keeps this regression focused on the antenna/channel
% producer while still exercising the exact PRACH waveform and CDL object.
result = sixgr.phy.ra.runFourStepRA(cfgRuntime, ...
    "RunFolder", runRoot, ...
    "RunId", "test_ra_physical_element_projection", ...
    "ScenarioName", "test_ra_physical_element_projection", ...
    "UEId", 1, "CellId", 1, "AttemptId", 1, ...
    "RuntimeIntegrationMode", "coupled_truth_runtime", ...
    "UseRuntimeChannel", true, ...
    "RuntimeNoiseSNR_dB", 30, ...
    "RuntimeSlot", 2, ...
    "FaultMode", "no_prach_detected", ...
    "WriteArtifacts", false);

assert(~contains(string(result.FailureReason), ...
    "RequiredAntennaPatternPortMismatch"), ...
    "The measured Msg1 stage must not fail while binding the physical array.");
T = result.RuntimeStageRows;
msg1 = T(string(T.StageName) == "Msg1", :);
assert(height(msg1) == 1 && logical(msg1.RuntimeChannelStateUsed), ...
    "The exact Msg1 waveform must traverse one persistent runtime channel state.");
assert(double(msg1.TxPortCount) == 1, ...
    "The configured PRACH waveform must remain one logical transmit port.");
assert(logical(msg1.RuntimeChannelElementExpansionApplied) && ...
    double(msg1.RuntimeChannelPhysicalTxElements) == 2, ...
    ["The one-port PRACH waveform must be power-preservingly projected " ...
     "onto the configured two-element UE array before CDL propagation."]);
assert(double(msg1.RxPortCount) == 2, ...
    "The gNB receiver must expose both configured physical receive elements.");
assert(strlength(strtrim(string(msg1.TxPortToElementMappingSource))) > 0, ...
    "The measured Msg1 row must disclose its port-to-element mapping authority.");
assert(logical(msg1.ChannelFadingApplied), ...
    "The focused Msg1 regression must traverse the configured fading object.");

ok = true;
fprintf('%s\n', char("PASS testFourStepRAPhysicalElementProjection: " + ...
    "one logical Msg1 port traversed two physical UE elements and " + ...
    "two gNB receive elements."));
end

function localCleanup(pathText)
if isfolder(pathText)
    rmdir(pathText, "s");
end
end
