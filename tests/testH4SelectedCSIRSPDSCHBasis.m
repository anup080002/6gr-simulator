function ok = testH4SelectedCSIRSPDSCHBasis()
%TESTH4SELECTEDCSIRSPDSCHBASIS Freeze CRI beam basis before applying PMI.
%
% The H4 cell has eight four-port CSI-RS beam states over 64 physical
% elements.  A received CRI selects one of those bases; PMI then maps data
% layers within the selected CSI-port basis.  The PDSCH physical precoder
% must therefore be B_CSIRS(CRI)*W_PMI, not a projection into the scenario's
% bootstrap PDSCH basis.

setup6GRSimToolkit("Verbose", false);
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    "simulator", "configs", "scenarios", ...
    "h4_100_cdlc100_connected_impaired_40db_gate.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scenario, ...
    fullfile(tempdir, "h4_selected_csirs_pdsch_basis"));
[cfg, ~] = sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg, 31, 2);

baseGrant = localGrant(cfg);
baseGrant = withAuthoredPDSCHDCI(cfg, baseGrant);
[candidates, ~] = sixgr.phy.dl.pmiCodebookCandidates( ...
    cfg, 1, 4, "Mode", "type1_su_mimo");
selectedPMI = 4;
Wcsi = double(candidates(selectedPMI + 1).W);

frozen = cell(1, 2);
selectedCRIs = [0 3];
for ordinal = 1:numel(selectedCRIs)
    cri = selectedCRIs(ordinal);
    grant = baseGrant;
    grant.CRI = cri;
    grant.PMI = selectedPMI;
    grant.AppliedPrecoderPMI = selectedPMI;
    grant.GrantContextId = "DL|h4-selected-csirs-basis|cri=" + string(cri);
    phyGrant = sixgr.phy.grant.freezePHYGrant(cfg, "DL", grant, ...
        "SNR_dB", 40, "Frame", 1, "Slot", grant.Slot);
    B = complex(double(cfg.phy.csirs.precoderMatrices(:,:,cri + 1)));
    expected = B * Wcsi;

    assert(logical(phyGrant.PrecodingState.CSIRSPortBasisApplied) && ...
        double(phyGrant.PrecodingState.CSIResourceIndex) == cri, ...
        "Frozen grant lost selected CSI-RS resource identity.");
    assert(norm(double(phyGrant.PrecodingState.MatrixLogicalPorts) - ...
            Wcsi, "fro") < 1e-12, ...
        "PMI matrix must remain in the selected four-port CSI-RS basis.");
    assert(norm(double(phyGrant.PrecodingState.HybridElementToPortMatrix) - ...
            B, "fro") < 1e-12, ...
        "Selected CRI must freeze its exact 64x4 CSI-RS basis for PDSCH.");
    assert(norm(double(phyGrant.PrecodingState.MatrixPhysicalPorts) - ...
            expected, "fro") < 1e-12, ...
        "Physical PDSCH precoder must equal B_CSIRS(CRI)*W_PMI.");
    assert(string(phyGrant.PrecodingState.HybridRFDesignPolicy) == ...
            "selected_cri_csirs_basis_plus_pmi" && ...
        string(phyGrant.PrecodingState.HybridRFDesignStatus) == ...
            "frozen_selected_csirs_basis", ...
        "Frozen grant must label the selected-CRI hybrid beam contract.");
    frozen{ordinal} = phyGrant;
end

assert(norm(double(frozen{1}.PrecodingState.MatrixPhysicalPorts) - ...
        double(frozen{2}.PrecodingState.MatrixPhysicalPorts), "fro") > 1e-3, ...
    "Distinct CRIs must produce distinct immutable physical PDSCH beams.");
assert(double(frozen{1}.PrecodingState.CSIResourceIndex) == 0, ...
    "Freezing a later grant must not mutate an already-issued grant.");

mismatched = baseGrant;
mismatched.CRI = 3;
mismatched.PMI = selectedPMI;
mismatched.AppliedPrecoderPMI = selectedPMI;
mismatched.HybridElementToPortMatrix = ...
    double(cfg.phy.csirs.precoderMatrices(:,:,1));
try
    sixgr.phy.grant.freezePHYGrant(cfg, "DL", mismatched, ...
        "SNR_dB", 40, "Frame", 1, "Slot", mismatched.Slot);
    error("testH4SelectedCSIRSPDSCHBasis:ExpectedMismatch", ...
        "A stale frozen hybrid basis was incorrectly accepted.");
catch ME
    assert(string(ME.identifier) == ...
        "sixgr:phy:grant:FrozenHybridCSIRSBasisMismatch", ...
        "Unexpected stale-basis failure: %s", ME.message);
end

ok = true;
fprintf("[PASS] H4 received-CRI CSI-RS basis is frozen before PMI application.\n");
end

function grant = localGrant(cfg)
pdsch = cfg.phy.pdsch;
carrier = sixgr.phy.grid.makeCarrier(cfg);
absoluteSlot0 = double(carrier.NFrame) * double(carrier.SlotsPerFrame) + ...
    double(carrier.NSlot);
grant = struct( ...
    "Direction", "DL", "Frame", double(carrier.NFrame) + 1, ...
    "Slot", absoluteSlot0 + 1, ...
    "RNTI", double(pdsch.RNTI), "UEIndex", 1, "ServingCell", 1, ...
    "PRBSet", double(pdsch.prbSet(:).'), ...
    "SymbolAllocation", double(pdsch.symbolAllocation(:).'), ...
    "Modulation", char(string(pdsch.modulation)), ...
    "NumLayers", 1, "Layers", 1, "NumLogicalPorts", 4, ...
    "TargetCodeRate", double(pdsch.codeRate), ...
    "MCSIndex", double(pdsch.mcsIndex), "MCS", double(pdsch.mcsIndex), ...
    "PrecodingMatrix", [], "PrecodingActive", true, ...
    "ExactPHYFeasibilityChecked", true, "ExactPHYFeasible", true, ...
    "GrantContextId", "DL|h4-selected-csirs-basis", "K0", 0, ...
    "HARQ", struct("HarqID", 0, "NDI", true, "RV", 0, ...
        "IsRetransmission", false));
end
