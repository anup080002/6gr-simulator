function ok = test6GLLSMultiUserBeamforming()
%TEST6GLLSMULTIUSERBEAMFORMING Ensure config-driven LLS keeps multi-user beamformed MIMO honest.

setup6GRSimToolkit("Verbose", false);

previousScratch = string(getenv("SIXGR_REGRESSION_SCRATCH_ROOT"));
scratchRoot = previousScratch;
ownsScratchRoot = strlength(strtrim(scratchRoot)) == 0;
if ownsScratchRoot
    scratchRoot = string(tempname);
    mkdir(scratchRoot);
    setenv("SIXGR_REGRESSION_SCRATCH_ROOT", scratchRoot);
elseif ~isfolder(scratchRoot)
    mkdir(scratchRoot);
end
scratchCleanup = onCleanup(@() localRestoreScratch(previousScratch, scratchRoot, ownsScratchRoot)); %#ok<NASGU>
tmp = localScratchChild(scratchRoot, "u", ownsScratchRoot);
mkdir(tmp);
c = onCleanup(@() localRemoveFolder(tmp)); %#ok<NASGU>

baseScenario = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "lls_mimo4x4_multiuser_beamformed_cdl_d_fdd_validation.yaml");
scenarioPath = fullfile(tmp, "lls_multiuser_smoke.yaml");
fid = fopen(scenarioPath, "w");
fprintf(fid, "%s", ['{' ...
    '"inherits":["' strrep(baseScenario, '\', '\\') '"],' ...
    '"meta":{"scenario_id":"lls_multiuser_smoke","description":"multi-user smoke","version":"1","owner":"test","maturity_tag":"smoke"},' ...
    '"simulation":{"n_frames":1,"n_slots":12,"monte_carlo_iterations":1,"random_seed":19,"snr_db":34},' ...
    '"run_control":{"total_slots":12,"total_time_ms":6,"warmup_slots":0,"measurement_slots":12},' ...
    '"pdsch":{"execution_profile":"scheduler_truth"},' ...
    '"pusch":{"execution_profile":"scheduler_truth"},' ...
    '"rf_frontend":{"ul_power_control":{"pusch":{"p0_ue_db":0}}},' ...
    '"csi_acquisition_and_reporting":{"csi_report_periodicity_slots":4,"csi_report_offset_slots":0},' ...
    '"reference_signals":{"srs_periodicity_slots":1,"srs_slot_within_period":[1],"srs_max_ues_per_slot":1,"srs_scheduling_policy":"round_robin_phase","srs":{"period_offset":0}},' ...
    '"control_gating":{"pbch_required":false,"prach_required":false,"pdcch_required":false,"srs_required":false,"srs_max_age_slots":4,"trs_required":false},' ...
    '"users":{"enabled":true,"n_users":2,"rnti_start":101,"seed_stride":29,' ...
    '"execution_model":"slot_coupled_truth","beam_selection_strategy":"round_robin_codebook","save_user_tables":true},' ...
    '"output":{"save_figures":false,"save_mat":false,"profile":"lls_multiuser_smoke"}}']);
fclose(fid);

resolvedScenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
resolvedCfg = sixgr.lls6g.buildInternalConfig(resolvedScenario, ...
    fullfile(tmp, "configuration_gate"));
reportRequest = sixgr.util.structGet(resolvedCfg, ...
    "phy.csi.reportConfiguration", struct());
assert(isstruct(reportRequest) && ~isempty(fieldnames(reportRequest)), ...
    "Enabled CSI reporting must resolve a typed report before waveform execution.");
assert(string(reportRequest.ReportConfigID) == "csi-report-mu4t4r-0" && ...
    reportRequest.Ports == 4 && reportRequest.Rank == 2 && ...
    reportRequest.N1 == 2 && reportRequest.N2 == 1 && ...
    reportRequest.O1 == 4 && reportRequest.O2 == 1, ...
    "The resolved CSI report does not match the configured 4-port Type-I tuple.");
assert(double(sixgr.util.structGet(resolvedCfg, ...
    "phy.csi.maxRank", NaN)) == 2 && ...
    isequal(double(sixgr.util.structGet(resolvedCfg, ...
    "phy.csi.rankDomain", [])), [1 2]), ...
    ["The non-strict runtime must bind CSI RI search to the active " ...
     "rank-2 report/PDSCH authority before waveform execution."]);
assert(double(sixgr.util.structGet(resolvedCfg, ...
    "phy.csi.reportPeriodicitySlots", NaN)) == 4 && ...
    double(sixgr.util.structGet(resolvedCfg, ...
    "phy.csi.reportOffsetSlots", NaN)) == 0, ...
    ["The bounded 12-slot FDD waveform test requires an explicit four-slot " ...
     "periodic CSI report, rather than inheriting the valid but much slower " ...
     "20 ms production reporting cycle."]);
sixgr.phy.mimo.CSIReportConfiguration(reportRequest, ...
    double(reportRequest.Epoch));
assert(logical(sixgr.util.structGet(resolvedCfg, ...
    "rf.frontend.ul_power_control.enabled", false)) && ...
    logical(sixgr.util.structGet(resolvedCfg, ...
    "rf.frontend.ul_power_control.open_loop_enabled", false)), ...
    "The multi-user runtime must retain explicit duplex-neutral UL power-control authority.");
assert(all(isfinite([ ...
    double(sixgr.util.structGet(resolvedCfg, "rf.frontend.ul_power_control.srs.p0_dbm", NaN)), ...
    double(sixgr.util.structGet(resolvedCfg, "rf.frontend.ul_power_control.srs.alpha", NaN)), ...
    double(sixgr.util.structGet(resolvedCfg, "rf.frontend.ul_power_control.srs.delta_tf_db", NaN)), ...
    double(sixgr.util.structGet(resolvedCfg, "rf.frontend.ul_power_control.srs.pcmax_dbm", NaN))])), ...
    "The multi-user runtime must retain all TS 38.213 SRS power-control inputs.");
assert(logical(sixgr.util.structGet(resolvedCfg, ...
    "phy.pucch.detectPUCCHPUSCHOverlap", false)) && ...
    logical(sixgr.util.structGet(resolvedCfg, ...
    "phy.pucch.uciOnPUSCHEnabled", false)) && ...
    string(sixgr.util.structGet(resolvedCfg, ...
    "phy.pucch.unsupportedOverlapPolicy", "")) == "reject_before_waveform", ...
    "The multi-user runtime must explicitly enable UCI-on-PUSCH overlap resolution.");

out = run_6g_phy_lls_single(scenarioPath, tmp, "smoke");
assert(out.Ok, ...
    "Runtime-array CDL-D FDD multi-user validation scenario should complete cleanly.");

runFolder = char(string(out.RunFolder));
dlFile = fullfile(runFolder, "air_interface", "csv", "dl_pdsch_trials.csv");
ulFile = fullfile(runFolder, "air_interface", "csv", "ul_pusch_trials.csv");
beamFile = fullfile(runFolder, "beamforming", "csv", "probe_beam_mimo.csv");
summaryFile = fullfile(runFolder, "air_interface", "csv", "multiuser_user_summary.csv");
csiRSFile = fullfile(runFolder, "air_interface", "csv", "csi_rs_trials.csv");
csiReportFile = fullfile(runFolder, "air_interface", "csv", "csi_feedback_reports.csv");

assert(exist(dlFile, "file") == 2, "Missing multi-user DL trials CSV.");
assert(exist(ulFile, "file") == 2, "Missing multi-user UL trials CSV.");
assert(exist(beamFile, "file") == 2, "Missing multi-user beamforming CSV.");
assert(exist(summaryFile, "file") == 2, "Missing multi-user summary CSV.");
assert(exist(csiRSFile, "file") == 2, "Missing measured CSI-RS trials CSV.");
assert(exist(csiReportFile, "file") == 2, "Missing causal CSI feedback report CSV.");

dl = readtable(dlFile, "VariableNamingRule", "preserve");
ul = readtable(ulFile, "VariableNamingRule", "preserve");
beam = readtable(beamFile, "VariableNamingRule", "preserve");
summary = readtable(summaryFile, "VariableNamingRule", "preserve");
csiRS = readtable(csiRSFile, "VariableNamingRule", "preserve");
csiReports = readtable(csiReportFile, "VariableNamingRule", "preserve");
dlCSIReports = csiReports(string(csiReports.Direction) == "DL", :);
for sourceSlot = [1 5 9]
    rows = round(double(dlCSIReports.SourceSlot)) == sourceSlot;
    assert(nnz(rows) == 2 && ...
        all(round(double(dlCSIReports.SpatialSignatureSourceSlot(rows))) == sourceSlot), ...
        ["Every configured four-slot CSI report occasion must preserve both " ...
         "UEs' measured CSI-RS producer slot; source slot %d is missing or stale."], ...
        sourceSlot);
end

assert(ismember("UEIndex", dl.Properties.VariableNames), "DL trials must expose UEIndex.");
assert(ismember("UEIndex", ul.Properties.VariableNames), "UL trials must expose UEIndex.");
assert(numel(unique(double(dl.UEIndex))) >= 2, "DL trials must cover multiple UEs.");
assert(numel(unique(double(ul.UEIndex))) >= 2, "UL trials must cover multiple UEs.");
assert(any(double(dl.ConfiguredTxAntennas) == 4), "DL trials must preserve 4T transmit configuration.");
assert(any(double(ul.ConfiguredTxAntennas) == 4), "UL trials must preserve 4T transmit configuration.");
assert(any(double(dl.ConfiguredLayers) == 2), "DL trials must preserve the configured layer count.");
assert(any(double(ul.ConfiguredLayers) == 2), "UL trials must preserve the configured layer count.");
assert(all(double(dl.Layers) == 2), "DL waveform trials must execute at two layers in this scenario.");
assert(all(double(ul.Layers) == 2), "UL waveform trials must execute at two layers in this scenario.");
assert(any(double(dl.CRCPass) == 1), ...
    "The high-SNR four-port DL waveform qualification must decode measured transport blocks.");
assert(any(double(ul.CRCPass) == 1), ...
    "The high-SNR four-port UL waveform qualification must decode measured transport blocks.");
localAssertULFailureDrivesAdaptation(ul);
localAssertULSharedSlotPowerDomain(ul);
assert(ismember("MUMIMOGroupSize", string(dl.Properties.VariableNames)) && ...
    any(double(dl.MUMIMOGroupSize) >= 2), ...
    ["Measured CSI feedback must cause at least one simultaneous multi-user " ...
     "DL waveform group; two independent single-user rows are not MU-MIMO truth."]);
muDLRows = double(dl.MUMIMOGroupSize) >= 2;
assert(any(muDLRows & double(dl.CRCPass) == 1), ...
    ["At least one measured shared-PRB MU-MIMO PDSCH transport block must " ...
     "decode; successful SU rows cannot qualify the MU data path."]);
requiredMUContract = ["MUMIMOSpatialDesignContractVersion", ...
    "MUMIMOSpatialSignatureSubspaceMode", ...
    "MUMIMOSpatialDesignEvidenceSource", "MUMIMOTransmitArchitecture"];
assert(all(ismember(requiredMUContract, string(dl.Properties.VariableNames))), ...
    "MU-MIMO DL rows must export the complete versioned spatial-design contract.");
assert(all(string(dl.MUMIMOSpatialDesignContractVersion(muDLRows)) == ...
        "MeasuredMUMIMOPairDesign/v13") && ...
    all(string(dl.MUMIMOSpatialSignatureSubspaceMode(muDLRows)) == ...
        "dominant_scheduled_rank"), ...
    ["The configured dominant-rank admission policy and v13 design contract " ...
     "must survive unchanged into every measured MU waveform row."]);
if ismember("MUMIMOGroupSize", string(ul.Properties.VariableNames))
    muULRows = double(ul.MUMIMOGroupSize) >= 2;
    assert(any(muULRows), ...
        "The enabled UL MU-MIMO scenario must execute a shared-slot PUSCH group.");
    assert(any(muULRows & double(ul.CRCPass) == 1), ...
        ["At least one shared-slot UL MU-MIMO PUSCH transport block must " ...
         "decode; successful isolated PUSCH rows are insufficient."]);
end
assert(ismember("MUMIMOPrecoderType", string(dl.Properties.VariableNames)) && ...
    any(string(dl.MUMIMOPrecoderType) == ...
        "measured_csirs_block_diagonalization"), ...
    "FDD MU-MIMO must apply the measured CSI-RS block-diagonalizing precoder.");
assert(ismember("ExecutionProfile", dl.Properties.VariableNames) && ...
    all(string(dl.ExecutionProfile) == "scheduler_truth"), ...
    "Multi-user CDL-D validation must execute decoded scheduler-owned grants.");
localAssertPerLayerSINR(dl, "DL", 2);
localAssertPerLayerSINR(ul, "UL", 2);
assert(ismember("BeamIndexSet", beam.Properties.VariableNames), "Beam diagnostics must export selected beam indices.");
assert(ismember("PrecoderSource", beam.Properties.VariableNames), "Beam diagnostics must expose precoder provenance.");
assert(any(strlength(string(beam.BeamIndexSet)) > 0), "Beam diagnostics must include selected beam indices.");
assert(any(logical(beam.BeamformingApplied)), "Beam diagnostics must mark applied beamforming.");
assert(ismember("ExecutionModel", summary.Properties.VariableNames), "Multi-user summary must expose execution model.");
assert(all(string(summary.ExecutionModel) == "slot_coupled_truth"), ...
    "Multi-user summary must honestly declare the coupled execution model.");
localAssertMeasuredFDDSpatialAuthority(csiRS);

manifest = jsondecode(fileread(fullfile(runFolder, "meta", "scenario_manifest.json")));
assert(isfield(manifest, "ConfiguredUsers") && manifest.ConfiguredUsers == 2, ...
    "Manifest must persist the configured user count.");
assert(isfield(manifest, "ConfiguredLayers") && manifest.ConfiguredLayers == 2, ...
    "Manifest must persist the configured layer count.");
assert(isfield(manifest, "BeamSelectionStrategy"), ...
    "Manifest must persist the beam selection strategy.");
assert(~isempty(summary), "Multi-user summary must not be empty.");

ok = true;
end

function localAssertULFailureDrivesAdaptation(T)
failed = double(T.CRCPass) == 0;
if ~any(failed)
    return;
end
required = ["MCSIndex", "LinkAdaptationApplied", ...
    "AppliedLinkAdaptationOLLAUpdateCount"];
assert(all(ismember(required, string(T.Properties.VariableNames))), ...
    "UL failure rows must retain the runtime link-adaptation/OLLA ledger.");
assert(any(logical(T.LinkAdaptationApplied)), ...
    "Measured UL failures occurred while link adaptation was never applied.");

recovered = false;
for ue = reshape(unique(double(T.UEIndex(failed))), 1, [])
    ueRows = find(double(T.UEIndex) == ue);
    [~, order] = sort(double(T.Slot(ueRows)));
    ueRows = ueRows(order);
    ueFail = ueRows(double(T.CRCPass(ueRows)) == 0);
    for row = reshape(ueFail, 1, [])
        later = ueRows(double(T.Slot(ueRows)) > double(T.Slot(row)));
        if any(double(T.MCSIndex(later)) < double(T.MCSIndex(row))) || ...
                any(double(T.AppliedLinkAdaptationOLLAUpdateCount(later)) > ...
                    double(T.AppliedLinkAdaptationOLLAUpdateCount(row)))
            recovered = true;
            break;
        end
    end
    if recovered
        break;
    end
end
assert(recovered, ...
    ["A measured PUSCH CRC failure never changed the later YAML-enabled " ...
     "CQI/OLLA operating authority."]);
end

function localAssertULSharedSlotPowerDomain(T)
required = ["DesiredSignalPowerBeforeNoise", ...
    "CompositeSignalPowerBeforeNoise", ...
    "InterferenceContributorCount", ...
    "PUSCHTxPower_dBm", ...
    "PUSCHMeasuredWaveformPower_dBm", ...
    "PUSCHPowerClosureError_dB"];
assert(all(ismember(required, string(T.Properties.VariableNames))), ...
    "UL trials are missing the absolute-power and shared-slot closure ledger.");

txPower = double(T.PUSCHTxPower_dBm);
measuredPower = double(T.PUSCHMeasuredWaveformPower_dBm);
closure = double(T.PUSCHPowerClosureError_dB);
assert(all(isfinite(txPower)) && all(isfinite(measuredPower)) && ...
    all(abs(txPower - measuredPower) <= 0.05) && ...
    all(isfinite(closure)) && all(abs(closure) <= 0.05), ...
    ["Every PUSCH must close at the YAML/TS 38.213 transmit-power " ...
     "reference plane before channel superposition."]);

shared = double(T.InterferenceContributorCount) > 0;
assert(any(shared), ...
    "The multi-user qualification must execute at least one shared-slot PUSCH pair.");
desired = double(T.DesiredSignalPowerBeforeNoise(shared));
composite = double(T.CompositeSignalPowerBeforeNoise(shared));
assert(all(isfinite(desired)) && all(desired > 0) && ...
    all(isfinite(composite)) && all(composite >= 0), ...
    "Shared-slot PUSCH rows must expose finite measured receiver powers.");
powerRatio_dB = 10 .* log10(max(composite, realmin) ./ max(desired, realmin));
assert(all(abs(powerRatio_dB) <= 20), ...
    ["Desired and coupled PUSCH waveforms occupy different physical " ...
     "power domains; composite/desired ratio reached %.3f dB."], ...
    max(abs(powerRatio_dB)));
end

function localAssertMeasuredFDDSpatialAuthority(T)
required = ["CSIRSPhysicalPortCount", "CSIRSWaveformPortCount", ...
    "SpatialSignatureToken", "SpatialSignatureSHA256", ...
    "SpatialSignatureMeasurementDirection", ...
    "SpatialSignatureReciprocityMode", "SpatialSignatureDomain", ...
    "SpatialSignatureStatus"];
assert(all(ismember(required, string(T.Properties.VariableNames))), ...
    "CSI-RS evidence is missing the measured FDD spatial-authority contract.");
rows = find(double(T.CSIRSPhysicalPortCount) == 4 & ...
    double(T.CSIRSWaveformPortCount) == 4 & ...
    string(T.SpatialSignatureStatus) == ...
        "available_measured_fdd_dl_transmit_subspace");
assert(~isempty(rows), ...
    "The four-port FDD CSI-RS waveform did not produce measured transmit-subspace authority.");
for ii = reshape(rows, 1, [])
    signature = sixgr.phy.mimo.MatrixContract.deserialize( ...
        string(T.SpatialSignatureToken(ii)));
    assert(size(signature, 1) == 4 && size(signature, 2) == 2, ...
        ["FDD CSI-RS spatial authority must retain the four physical " ...
         "transmit ports and exactly the configured two-layer subspace; " ...
         "got %dx%d at row %d."], ...
        size(signature, 1), size(signature, 2), ii);
    assert(string(T.SpatialSignatureMeasurementDirection(ii)) == "DL" && ...
        string(T.SpatialSignatureReciprocityMode(ii)) == "direct_dl_csirs" && ...
        string(T.SpatialSignatureDomain(ii)) == "transmitter", ...
        "FDD CSI-RS spatial authority has incorrect direction/domain provenance.");
    assert(string(T.SpatialSignatureSHA256(ii)) == ...
        sixgr.phy.mimo.MatrixContract.digest(signature), ...
        "FDD CSI-RS spatial-authority digest does not match its matrix payload.");
end
end

function localAssertPerLayerSINR(T, linkLabel, expectedLayers)
vars = string(T.Properties.VariableNames);
assert(ismember("PostEqSINRPerLayer_dB", vars), ...
    "%s trials must export per-layer post-equalization SINR.", linkLabel);

if ismember("Layers", vars)
    rows = find(double(T.Layers) == expectedLayers);
else
    rows = (1:height(T)).';
end
assert(~isempty(rows), "%s trials must include %d-layer rows.", linkLabel, expectedLayers);

tokens = string(T.PostEqSINRPerLayer_dB);
for ii = reshape(rows, 1, [])
    values = localParseNumericVector(tokens(ii));
    assert(numel(values) == expectedLayers, ...
        "%s row %d must expose one post-equalization SINR value per layer; got '%s'.", ...
        linkLabel, ii, char(tokens(ii)));
    assert(all(isfinite(values)), ...
        "%s row %d per-layer post-equalization SINR must be finite.", linkLabel, ii);
end
end

function values = localParseNumericVector(token)
token = string(token);
if ismissing(token) || strlength(strtrim(token)) == 0
    values = [];
    return;
end

raw = char(token);
raw = strrep(raw, "[", "");
raw = strrep(raw, "]", "");
parts = regexp(raw, "[\|\s,;]+", "split");
parts = parts(~cellfun(@isempty, parts));
values = str2double(parts);
end

function localRestoreScratch(previousScratch, scratchRoot, ownsScratchRoot)
setenv("SIXGR_REGRESSION_SCRATCH_ROOT", previousScratch);
if ownsScratchRoot
    localRemoveFolder(scratchRoot);
end
end

function pathValue = localScratchChild(scratchRoot, prefix, ownsScratchRoot)
if ownsScratchRoot
    pathValue = fullfile(scratchRoot, prefix);
else
    token = char(java.util.UUID.randomUUID());
    pathValue = fullfile(scratchRoot, prefix + string(token(1:8)));
end
end

function localRemoveFolder(pathValue)
if isfolder(pathValue)
    rmdir(pathValue, "s");
end
end
