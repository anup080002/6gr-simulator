function testRFImpairmentChainApplied
T = channelRFStrictAnchorResult().Result.RFImpairmentChain;
assert(height(T) > 0, "RF impairment chain evidence must be exported.");
assert(all(T.WaveformChanged), "RF impairment chain must mutate waveform samples.");
assert(all(T.CFOEnabled & T.IQImbalanceEnabled & T.PAEnabled), ...
    "Strict mini RF chain must apply CFO, IQ imbalance, and PA nonlinearity.");
assert(all(isfinite(T.EVMMeasuredPercent) & T.EVMMeasuredPercent > 0), ...
    "RF EVM must be measured from before/after samples.");

cfg = channelRFStrictAnchorResult().Config;
cfg = sixgr.util.structSet(cfg, "phy.impairments.phaseNoiseEnabled", true);
cfg = sixgr.util.structSet(cfg, "rf.phaseNoise.enable", true);
out = sixgr.rf.applyRFImpairmentChain(complex(ones(4096, 1)), cfg, ...
    "SampleRateHz", double(sixgr.util.structGet(cfg, "channel_rf.sampleRateHz", 30.72e6)), ...
    "RunId", "phase_noise_channel_rf_guard");
row = struct2table(out.Row);
assert(logical(row.PhaseNoiseEnabled) && logical(row.PhaseNoiseApplied), ...
    "Configured phase noise must be applied in the strict Channel/RF RF chain.");
assert(strcmpi(char(string(row.PhaseNoiseExecutionStatus)), "applied_sample_domain_phase_noise"), ...
    "Strict Channel/RF phase-noise evidence must disclose sample-domain application.");
assert(string(row.PhaseNoiseWaveformBeforeHash) ~= string(row.PhaseNoiseWaveformAfterHash), ...
    "Phase-noise evidence must include changed before/after waveform hashes.");
end
