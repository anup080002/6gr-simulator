function ok = testSSBBeamSweepRank2DataPrecoderIsolation()
%TESTSSBBEAMSWEEPRANK2DATAPRECODERISOLATION Keep SI and data grants separate.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile(pwd, ...
    "simulator", "configs", "scenarios", ...
    "lls_tdd_5mhz_rank2_shared_awgn_20db.yaml"));
tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() localCleanup(tmp)); %#ok<NASGU>
cfg = sixgr.lls6g.buildInternalConfig(scenario, tmp);

assert(double(sixgr.util.structGet(cfg, "phy.pdsch.numLayers", NaN)) == 1 && ...
    double(sixgr.util.structGet(cfg, "phy.csi.maxRank", NaN)) == 2, ...
    "Target TDD scenario must retain bootstrap rank one and measured rank-two capability.");
% CoupledTruthRuntime freezes this exact-shaped immutable matrix when the
% rank-2 DL grant is materialized.  Reproduce the persisted post-runtime
% configuration passed to bundle finalization.
numPorts=double(sixgr.util.structGet(cfg,"phy.nTxAnt",NaN));
assert(isfinite(numPorts) && numPorts>=2);
dataMatrix=eye(numPorts,2)/sqrt(2);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.numLayers", 2);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.nLayers", 2);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.precoding.matrix", dataMatrix);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.precodingMatrix", dataMatrix);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.W", dataMatrix);

% SIB1 is SI-RNTI common PDSCH and is independently materialized as a
% single-layer broadcast allocation.  A data-grant matrix must neither be
% reshaped nor silently reused at this procedure boundary.
cfg = sixgr.util.structSet(cfg, "channel.snr_dB", 20);
out = sixgr.link.runSSBBeamSweep(cfg, ...
    "SNR_dB", 20, "NumSubframes", 5, "MaxBeams", 4);
evidenceFolder=fullfile(pwd,'results','lls','ssb_tdd_rank2_precoder_isolation', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(evidenceFolder);
writetable(out.TrialTable,fullfile(evidenceFolder,'receiver_trials.csv'));
fprintf('SSB_TDD_COMPONENT_OUTPUT=%s\n',evidenceFolder);
assert(istable(out.TrialTable) && height(out.TrialTable) == 4, ...
    "Focused SSB beam sweep must physically execute all four configured beams.");
assert(all(~logical(out.TrialTable.Crash)), ...
    "SIB1 broadcast context inherited the rank-2 data-PDSCH precoder: %s", ...
    string(out.TrialTable.FailureReason(1)));
assert(all(logical(out.TrialTable.BCHCrcPass)) && ...
    all(logical(out.TrialTable.MIBDecoded)) && ...
    all(logical(out.TrialTable.SIB1StrictOk)), ...
    "Focused SSB/PBCH/MIB/SIB1 waveform acquisition did not pass: BCH=%d MIB=%d SIB1=%d reason=%s", ...
    out.TrialTable.BCHCrcPass(1),out.TrialTable.MIBDecoded(1), ...
    out.TrialTable.SIB1StrictOk(1),string(out.TrialTable.FailureReason(1)));
assert(all(logical(out.TrialTable.RuntimeChannelStateUsed)) && ...
    nnz(out.TrialTable.SelectedBeamFlag)==1 && ...
    all(string(out.TrialTable.SelectionStatus) == ...
        "selected_from_successful_receiver_measurements"), ...
    "SSB selection must be based on the executed runtime-channel receiver row.");
assert(all(isnan(out.TrialTable.SS_RSRP_dBm)) && ...
    out.SelectionMetric=="SS_RSRP_dB_re_UnitOccupiedRE_Es", ...
    'A normalized power experiment must not fabricate absolute dBm for beam selection.');
[bestPower,bestRow]=max(out.TrialTable.SS_RSRP_dB_re_UnitOccupiedRE_Es);
assert(out.SelectedSSBIndex==out.TrialTable.SSBIndex(bestRow) && ...
    out.SelectionMetricValue_dB==bestPower && ...
    all(out.TrialTable.SSBIndexMatch) && ...
    isequal(out.TrialTable.RecoveredSSBIndex,(0:3).'), ...
    'Selection must use actual recovered SSB identities and their own receiver power.');
assert(double(out.TrialTable.ConfiguredSNR_dB(1)) == 20 && ...
    strlength(string(out.TrialTable.SSBBurstPrecoderID(1))) > 0 && ...
    strlength(string(out.TrialTable.SSBBurstPrecoderMatrixSHA256(1))) == 64, ...
    "SSB sweep must bind execution SNR and absolute-index precoder provenance.");
ok = true;
end

function localCleanup(pathText)
if isfolder(pathText)
    rmdir(pathText, "s");
end
end
