function ok = testLLSPUSCHHARQACKRuntimeFeedback()
%TESTLLSPUSCHHARQACKRUNTIMEFEEDBACK Verify causal DL ACK transfer on PUSCH.

setup6GRSimToolkit("Verbose", false);

scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    "simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring.yaml"));
resolved = sixgr.lls6g.buildInternalConfig(scenario, tempdir);
assert(logical(sixgr.util.structGet(resolved, ...
    "phy.pucch.uciOnPUSCHEnabled", false)) && ...
    string(sixgr.util.structGet(resolved, ...
    "phy.pusch.uciMultiplexingMode", "")) == ...
    "harq_ack_on_pusch_when_pucch_collides", ...
    ["The causal production scenario must explicitly authorize same-UE " ...
    "HARQ-ACK multiplexing on colliding PUSCH; safe pucch_only fallback " ...
    "would otherwise starve UL data."]);

rnti = 811;
dueSlot = 5;
harq = sixgr.l2.mac.HARQEntityDL(struct());
feedbackRows = repmat(localFeedbackRow(), 2, 1);
transmittedGrants=cell(2,1);
for bitIdx = 1:2
    sourceSlot = bitIdx;
    txp = harq.allocate(rnti, sourceSlot, 8, "NewData", true);
    harqId0 = double(txp.HARQ.HarqID);
    grant = struct( ...
        "Direction", "DL", "RNTI", rnti, "TBSBits", 64, ...
        "TBSBytes", 8, "HARQ", txp.HARQ, ...
        "HARQTBContext", struct("TBId", sprintf("DL-%d-%d-%d", ...
        rnti, sourceSlot, harqId0), "TBSBits", 64));
    grant.Modulation='QPSK'; grant.NumLayers=1; grant.TargetCodeRate=.3;
    grant.CodingLayout=sixgr.phy.phycode.resolveCodingLayout( ...
        'Direction','DL','TransportBlockSize',64,'TargetCodeRate',.3, ...
        'RV',double(txp.HARQ.RV),'Modulation','QPSK','NumLayers',1, ...
        'RateMatchedBitCount',2*ceil((64+24)/.3/2));
    harq.onTx(rnti, harqId0, zeros(64, 1, "uint8"), grant, sourceSlot);
    transmittedGrants{bitIdx}=grant;

    feedbackRows(bitIdx).Direction = "DL";
    feedbackRows(bitIdx).UEIndex = 1;
    feedbackRows(bitIdx).RNTI = rnti;
    feedbackRows(bitIdx).HarqID = harqId0;
    feedbackRows(bitIdx).SourceSlot = sourceSlot;
    feedbackRows(bitIdx).DueSlot = dueSlot;
    feedbackRows(bitIdx).Ack = bitIdx == 1;
    feedbackRows(bitIdx).CurrentDecodeOK = bitIdx == 1;
    feedbackRows(bitIdx).CombinedDecodeOK = bitIdx == 1;
    feedbackRows(bitIdx).ServingCell = 1;
    feedbackRows(bitIdx).BaseStationID = 1;
    feedbackRows(bitIdx).ComponentCarrier=resolved.phy.frame.DefaultIdentity.ScheduledCCID;
    feedbackRows(bitIdx).ActiveULBWP=resolved.phy.frame.DefaultIdentity.ULBWPID;
    feedbackRows(bitIdx).TBSBits = 64;
    feedbackRows(bitIdx).UCIBitCount = 1;
    feedbackRows(bitIdx).RequestedFormat = 0;
    feedbackRows(bitIdx).ResolvedFormat = 0;
    feedbackRows(bitIdx).PUCCHResourceId = "0";
    feedbackRows(bitIdx).PUCCHPRBStart = 0;
    feedbackRows(bitIdx).PUCCHPRBCount = 1;
    feedbackRows(bitIdx).PUCCHSymbolStart = 12;
    feedbackRows(bitIdx).PUCCHNumSymbols = 2;
    feedbackRows(bitIdx).UCIType = "harq_ack";
    feedbackRows(bitIdx).ControlResourceSource = "focused_runtime_fixture";
    feedbackRows(bitIdx).ControlResourceValidity = true;
    feedbackRows(bitIdx).FormatAdaptationReason = "none_strict_assignment";
    feedbackRows(bitIdx).PUCCHGrantId = sprintf("PUCCH-GRANT-%d", bitIdx);
end

fixture = struct( ...
    "CurrentSlot", dueSlot, "CurrentFrame", 1, "CurrentSNR_dB", 20, ...
    "SlotsPerFrame", 10, "CfgMobility", resolved, ...
    "DLHarq", harq, "DLCombinedLLR", {cell(1, harq.NumProcesses)}, ...
    "DLSchedulers", {{[]}}, ...
    "PendingFeedbackTable", struct2table(feedbackRows), ...
    "PUCCHGrantTraceTable", table(), "HARQTimelineTable", table(), ...
    "HARQSummaryTable", table());
state=sixgr.truth.CoupledTruthRuntime.initialize(resolved,tempname, ...
    struct('Enabled',true,'NumUsers',1,'RNTIStart',rnti,'ExecutionModel','slot_coupled_truth'),struct(),10);
for field=string(fieldnames(fixture)).'
    state.(field)=fixture.(field);
end
state.CurrentServingIdx(:)=1; % Declared single-cell feedback owner, not a random-drop assertion.
state.DLCombinedLLR{1, 1} = ones(8, 1);
state.DLCombinedLLR{1, 2} = ones(8, 1);
for bitIdx = 1:2
    state = sixgr.truth.CoupledTruthRuntime.schedulePUCCHGrantRuntime( ...
        state, state.PendingFeedbackTable(bitIdx, :));
end

% Reproduce the complete-run ordering: the future K2 PUSCH exists before
% the PDSCH decoder creates its due HARQ-ACK rows.  Reconciliation must bind
% those late-created rows before startSlot can execute standalone PUCCH.
queuedBeforeFeedback = struct( ...
    "Direction", "UL", "UEIndex", 1, "RNTI", rnti, ...
    "GrantContextId", "UL-PUSCH-UCI-LATE-5", "Slot", dueSlot, ...
    "ScheduledAbsoluteSlot", dueSlot,"SymbolAllocation",[0 14]);
nonoverlap=queuedBeforeFeedback; nonoverlap.SymbolAllocation=[0 10];
for enabled=[false true]
    [separateState,separateGrant,separateBlocked]=sixgr.truth.CoupledTruthRuntime. ...
        reconcileQueuedPUSCHAfterDLFeedbackRuntime(state,nonoverlap,enabled);
    assert(isempty(separateBlocked) && numel(separateGrant)==1 && ...
        ~logical(sixgr.util.structGet(separateGrant,'UCIOnPUSCHApplied',false)) && ...
        ~any(separateState.PUCCHGrantTraceTable.MultiplexedOnPUSCH), ...
        'Nonoverlapping PUSCH/PUCCH symbols in one slot must retain separate transmissions.');
    touching=nonoverlap; touching.SymbolAllocation=[0 12];
    [~,touchingGrant,touchingBlocked]=sixgr.truth.CoupledTruthRuntime. ...
        reconcileQueuedPUSCHAfterDLFeedbackRuntime(state,touching,enabled);
    assert(isempty(touchingBlocked) && numel(touchingGrant)==1 && ...
        ~logical(sixgr.util.structGet(touchingGrant,'UCIOnPUSCHApplied',false)), ...
        'Half-open CP-OFDM intervals that only touch must not be multiplexed or suppressed.');
end
missingAllocation=rmfield(queuedBeforeFeedback,'SymbolAllocation');
localAssertError(@() sixgr.truth.CoupledTruthRuntime. ...
    reconcileQueuedPUSCHAfterDLFeedbackRuntime(state,missingAllocation,true), ...
    'sixgr:truth:MissingPUSCHOverlapAllocation');
foreign=queuedBeforeFeedback;
foreign.ActiveULBWP=state.CfgMobility.phy.frame.DefaultIdentity.ULBWPID+1;
localAssertError(@() sixgr.truth.CoupledTruthRuntime. ...
    reconcileQueuedPUSCHAfterDLFeedbackRuntime(state,foreign,true), ...
    'sixgr:truth:UnsupportedUCIOverlapCarrier');
planningSource=state; planningSource.CurrentCanonicalSlot=dueSlot;
planningSource.CurrentSweepPointIndex=1; planningSource.CurrentSweepPointCount=1;
planningSource.CanonicalSlotsPerSweepPoint=10;
planning=sixgr.truth.CoupledTruthRuntime.futureULPlanningView(planningSource,dueSlot);
beforeRNG=rng;
[planningAfter,planningGrant,planningBlocked]=sixgr.truth.CoupledTruthRuntime. ...
    reconcileQueuedPUSCHAfterDLFeedbackRuntime(planning,nonoverlap,true);
assert(isempty(planningBlocked) && numel(planningGrant)==1 && isequaln(beforeRNG,rng) && ...
    isequaln(planningAfter.ControlTrials,planning.ControlTrials), ...
    'A future UL overlap plan must neither execute PHY nor consume waveform RNG state.');
% Resource selection must account for the complete HARQ codebook. Three
% declared reducer-fixture ACK bits select format 2; its configured symbol
% start differs from the original one-bit format-0 reservations.
groupState=state;
rrc=groupState.CfgMobility.validation.pucch_resources;
format2=find([rrc.resources.format]==2);
assert(isscalar(format2));
rrc.resources(format2).starting_symbol=10;
groupState.CfgMobility.validation.pucch_resources=rrc;
third=groupState.PendingFeedbackTable(1,:);
third.SourceSlot=3; third.HarqID=2; third.PUCCHGrantId="PUCCH-GRANT-3";
groupState.PendingFeedbackTable=[groupState.PendingFeedbackTable;third];
groupState=sixgr.truth.CoupledTruthRuntime.schedulePUCCHGrantRuntime(groupState,third);
partial=queuedBeforeFeedback; partial.SymbolAllocation=[0 11];
for enabled=[false true]
    [planned,plannedGrant,plannedBlocked]=sixgr.truth.CoupledTruthRuntime. ...
        reconcileQueuedPUSCHAfterDLFeedbackRuntime(groupState,partial,enabled);
    assert(isempty(planned.ControlTrials.PUCCH), ...
        'Resource planning must not claim an executed PUCCH waveform.');
    if enabled
        assert(isempty(plannedBlocked) && ...
            isequal(plannedGrant.ExpectedUCIPayload.HARQACK,int8([1;0;1])), ...
            'Combined format-2 resource overlap must move the complete codebook onto PUSCH.');
    else
        assert(isempty(plannedGrant) && height(plannedBlocked)==1 && ...
            plannedBlocked.PUCCHStartTick<plannedBlocked.PUSCHEndTickExclusive, ...
            'The overlap guard must compare the combined format-2 allocation, not old format-0 rows.');
    end
end
% RNTI equality must not override distinct runtime UE owners (for example,
% reused cell-scoped radio identifiers). No waveform is claimed by this
% reducer fixture; the check is exact feedback/transport ownership.
otherUEGrant=queuedBeforeFeedback;
otherUEGrant.UEIndex=2; otherUEGrant.ServingCell=2;
[otherState,otherGrant,otherBlocked]=sixgr.truth.CoupledTruthRuntime. ...
    reconcileQueuedPUSCHAfterDLFeedbackRuntime(state,otherUEGrant,true);
assert(isempty(otherBlocked) && numel(otherGrant)==1 && ...
    ~logical(sixgr.util.structGet(otherGrant,'UCIOnPUSCHApplied',false)) && ...
    ~any(otherState.PUCCHGrantTraceTable.MultiplexedOnPUSCH), ...
    'A different runtime UE must not acquire another UE''s HARQ-ACK through RNTI equality.');
[~,otherGrant,otherBlocked]=sixgr.truth.CoupledTruthRuntime. ...
    reconcileQueuedPUSCHAfterDLFeedbackRuntime(state,otherUEGrant,false);
assert(isempty(otherBlocked) && numel(otherGrant)==1, ...
    'Another UE''s standalone PUCCH must not suppress this PUSCH through RNTI equality.');
% Exercise the production slot-entry boundary, not just its isolated
% overlap helper. These are declared reducer-test payloads, not PHY rows.
slotState=sixgr.truth.CoupledTruthRuntime.initialize(resolved,tempname, ...
    struct('Enabled',true,'NumUsers',1,'RNTIStart',rnti,'ExecutionModel','slot_coupled_truth'),struct(),10);
for field=["PendingFeedbackTable","PUCCHGrantTraceTable","DLHarq","DLCombinedLLR"]
    slotState.(field)=state.(field);
end
slotState.CurrentServingIdx(:)=1;
[slotState,slotGrant,slotBlocked]=sixgr.truth.CoupledTruthRuntime.startSlotWithQueuedUL( ...
    slotState,resolved,'UL',1,1,dueSlot,10,12,queuedBeforeFeedback,true);
assert(isempty(slotBlocked) && isequal(slotGrant.ExpectedUCIPayload.HARQACK,int8([1;0])) && ...
    all(slotState.PUCCHGrantTraceTable.MultiplexedOnPUSCH) && ...
    ~any(slotState.PUCCHGrantTraceTable.GrantExecutedFlag) && ...
    isempty(slotState.PUCCHExecutedCurrentSlotGrantSnapshot), ...
    'Slot entry must bind queued UL before any standalone PUCCH samples are emitted.');
[lateState, lateGrant, lateBlocked] = sixgr.truth.CoupledTruthRuntime. ...
    reconcileQueuedPUSCHAfterDLFeedbackRuntime( ...
    state, queuedBeforeFeedback, true);
assert(isempty(lateBlocked) && numel(lateGrant) == 1 && ...
    logical(lateGrant.UCIOnPUSCHApplied) && ...
    isequal(int8(lateGrant.ExpectedUCIBits(:)), int8([1; 0])) && ...
    all(string(lateState.PendingFeedbackTable.DeliveryMechanism) == "pusch_uci") && ...
    all(lateState.PUCCHGrantTraceTable.MultiplexedOnPUSCH), ...
    ["A PDSCH-created HARQ-ACK must late-bind to an already queued future " ...
    "PUSCH before standalone PUCCH execution."]);

blockedState = state;
[~, blockedGrant, blockedRows] = sixgr.truth.CoupledTruthRuntime. ...
    reconcileQueuedPUSCHAfterDLFeedbackRuntime( ...
    blockedState, queuedBeforeFeedback, false);
assert(isempty(blockedGrant) && height(blockedRows) == 1 && ...
    string(blockedRows.Reason(1)) == "pucch_pusch_time_overlap_same_ue", ...
    "Without UCI-on-PUSCH, the colliding queued PUSCH must be suppressed.");
assert(blockedRows.PUSCHStartTick<blockedRows.PUCCHEndTickExclusive && ...
    blockedRows.PUCCHStartTick<blockedRows.PUSCHEndTickExclusive && ...
    blockedRows.OverlapTimingDomain=="scheduled_common_ul_carrier_cp_ofdm_symbols", ...
    'Collision evidence must retain exact scheduled CP-OFDM intervals and its non-measurement domain.');
exportRoot=tempname;
exportState=blockedState;
exportState.ControlTrials.ULControlResourceDecisions=blockedRows;
exportState.ControlTrials.ULControlResourceDecisions.ValueSource="declared_scheduler_resource_component_fixture";
sixgr.truth.CoupledTruthRuntime.writeTables(exportState,exportRoot);
layout=sixgr.report.resultLayout(exportRoot);
for folder=[string(layout.ControlCSVDir),string(layout.AirInterfaceCSVDir)]
    exported=readtable(fullfile(folder,'ul_control_resource_decisions.csv'),'TextType','string');
    assert(height(exported)==height(blockedRows) && ...
        isequal(exported.PUSCHStartTick,blockedRows.PUSCHStartTick) && ...
        isequal(exported.PUSCHEndTickExclusive,blockedRows.PUSCHEndTickExclusive) && ...
        isequal(exported.PUCCHStartTick,blockedRows.PUCCHStartTick) && ...
        isequal(exported.PUCCHEndTickExclusive,blockedRows.PUCCHEndTickExclusive) && ...
        all(exported.OverlapTimingDomain==blockedRows.OverlapTimingDomain) && ...
        all(exported.ValueSource=="declared_scheduler_resource_component_fixture"), ...
        'Resource-decision CSV mirrors must preserve exact tick values and non-waveform provenance.');
end
fprintf('PUSCH_PUCCH_DECISION_CSV_ROUNDTRIP_PASS: %s\n',exportRoot);
[~,~,candidateKeep]=sixgr.truth.CoupledTruthRuntime.excludeULGrantsCollidingWithPUCCHRuntime( ...
    state,[nonoverlap;queuedBeforeFeedback],dueSlot);
assert(isequal(candidateKeep,[true false]), ...
    'Pre-DCI cancellation must identify only the actual overlapping candidate.');
code=fileread(which('sixgr.truth.runWaveformLinkBundle'));
first=strfind(code,'function [state, pendingULGrants] = localScheduleCoupledFutureULGrantsFromDLControl');
last=strfind(code,'function decision = localResolveCoupledULTimingDecision');
planner=code(first(1):last(1)-1);
guard=strfind(planner,'excludeULGrantsCollidingWithPUCCHRuntime(planState,candidates,dueSlot)');
dci=strfind(planner,'[state, qualifiedGrants] = localQualifyCoupledGrantsWithPDCCH');
assert(isscalar(guard) && isscalar(dci) && guard<dci && ...
    ~contains(planner,'planState.ULQueueBits('), ...
    'Main scheduler must inspect actual candidate overlap before DCI, without zeroing real queue inputs.');

% A nonempty bit vector is not proof of an exact UCI transfer.  Reject a
% partially populated/stale grant unless the immutable PUCCH grant IDs and
% typed payload were bound through the pending feedback ledger.
unboundBitsGrant = queuedBeforeFeedback;
unboundBitsGrant.ExpectedUCIBits = int8([1; 0]);
unboundBitsGrant.UCIOnPUSCHApplied = true;
[~, unboundGrant, unboundRows] = sixgr.truth.CoupledTruthRuntime. ...
    reconcileQueuedPUSCHAfterDLFeedbackRuntime( ...
    blockedState, unboundBitsGrant, false);
assert(isempty(unboundGrant) && height(unboundRows) == 1, ...
    "Unbound ExpectedUCIBits must not bypass the same-UE PUCCH/PUSCH " + ...
    "collision guard without exact typed-payload lineage.");

puschGrant = struct( ...
    "Direction", "UL", "UEIndex", 1, "RNTI", rnti, ...
    "GrantContextId", "UL-PUSCH-UCI-5", "Slot", dueSlot,"SymbolAllocation",[0 14]);
[state, puschGrant] = sixgr.truth.CoupledTruthRuntime. ...
    multiplexDueHARQACKOnPUSCHRuntime(state, puschGrant, dueSlot);
assert(logical(puschGrant.UCIOnPUSCHApplied) && ...
    isequal(int8(puschGrant.ExpectedUCIBits(:)), int8([1; 0])) && ...
    double(puschGrant.UCIOnPUSCHFeedbackBitCount) == 2, ...
    "All same-UE due DL HARQ bits must be placed on the qualified PUSCH grant.");
assert(all(string(state.PendingFeedbackTable.DeliveryMechanism) == "pusch_uci") && ...
    all(state.PUCCHGrantTraceTable.MultiplexedOnPUSCH) && ...
    isempty(sixgr.truth.CoupledTruthRuntime. ...
    pucchFeedbackDueHARQACKRuntime(state, dueSlot)), ...
    "Transferred feedback must be excluded from standalone PUCCH execution.");

harqOut = struct( ...
    "GrantSnapshot", puschGrant, ...
    "ExpectedHARQACKBits", int8([1; 0]), ...
    "DecodedHARQACKBits", int8([1; 1]), ...
    "HARQACKDecodeStatus", "decoded_mismatch", ...
    "HARQACKContentMatch", false);
% Declared wrong-ACK component input has actual short-code decoder evidence;
% transmitted-bit agreement must remain scoring-only (second bit false ACK).
coded=nrUCIEncode(harqOut.DecodedHARQACKBits,480,'QPSK');
[~,ackEvidence]=sixgr.phy.ul.pusch.decodeUCIWithEvidence(50*(1-2*double(coded)),2,'QPSK');
harqOut.UCIReceiverEvidence=struct('HARQACK',ackEvidence);
% A bad later binding must fail before the first valid ACK mutates a handle.
beforeStats=state.DLHarq.Stats; beforeProcesses=state.DLHarq.UEProcs;
beforeBuffers=state.DLCombinedLLR;
bad=state; bad.PendingFeedbackTable.DueSlot(2)=dueSlot+1;
localAssertError(@()sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHHARQACKRuntime(bad,harqOut), ...
    'sixgr:truth:InvalidPUSCHHARQACKRuntimeBinding');
assert(isequaln(state.DLHarq.Stats,beforeStats) && isequaln(state.DLHarq.UEProcs,beforeProcesses) && ...
    isequaln(state.DLCombinedLLR,beforeBuffers),'Late binding failure changed an earlier process.');
bad=state;
bad.HARQTimelineTable=table("DL",rnti,feedbackRows(1).HarqID,feedbackRows(1).SourceSlot, ...
    'VariableNames',{'Direction','RNTI','HarqID','Slot'});
localAssertError(@()sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHHARQACKRuntime(bad,harqOut), ...
    'sixgr:truth:InvalidPUSCHHARQACKTimelineBinding');
assert(isequaln(state.DLHarq.Stats,beforeStats) && isequaln(state.DLHarq.UEProcs,beforeProcesses), ...
    'A missing later timeline row changed an earlier process.');
bad=state; malformed=harqOut;
bad.PendingFeedbackTable.HarqID(2)=state.DLHarq.NumProcesses;
malformed.GrantSnapshot.UCIOnPUSCHFeedbackHARQIds(2)=state.DLHarq.NumProcesses;
localAssertError(@()sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHHARQACKRuntime(bad,malformed), ...
    'sixgr:HARQEntity:BadHarqId');
assert(isequaln(state.DLHarq.Stats,beforeStats) && isequaln(state.DLHarq.UEProcs,beforeProcesses), ...
    'An invalid later process changed an earlier process.');
for field=["ExpectedHARQACKBits","DecodedHARQACKBits"]
    malformed=harqOut; malformed.(field)=[1;.2];
    localAssertError(@()sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHHARQACKRuntime(state,malformed), ...
        'sixgr:truth:InvalidPUSCHHARQACKEvidence');
end
assert(isequaln(state.DLHarq.Stats,beforeStats) && isequaln(state.DLHarq.UEProcs,beforeProcesses));
% The same decoded short-code ACKs must not mutate newer process attempts.
% This is a declared MAC/UCI decoder fixture, not a shared waveform run.
staleState=state;
staleHARQ=sixgr.l2.mac.HARQEntityDL(struct());
for bitIdx=1:2
    txp=staleHARQ.allocate(rnti,bitIdx+2,8,'NewData',true);
    assert(txp.HARQ.HarqID==bitIdx-1);
    staleHARQ.onTx(rnti,bitIdx-1,zeros(64,1,'uint8'),transmittedGrants{bitIdx},bitIdx+2);
    staleHARQ.storeSoftBuffer(rnti,bitIdx-1,struct('LLRSum',ones(8,1),'ObservationWeight',1));
end
recorder=FeedbackDispositionRecorder();
staleState.DLHarq=staleHARQ; staleState.DLSchedulers={recorder};
staleState=sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHHARQACKRuntime(staleState,harqOut);
assert(staleHARQ.Stats.Ack==0 && staleHARQ.Stats.StaleFeedbackIgnored==2 && ...
    isempty(recorder.Updates) && all(cellfun(@(x)isequal(x,ones(8,1)),staleState.DLCombinedLLR(1,1:2))));
for pid=0:1
    assert(~isempty(fieldnames(staleHARQ.getSoftBuffer(rnti,pid))));
end
staleTrace=staleState.PUCCHGrantTraceTable;
assert(all(staleState.PendingFeedbackTable.Processed) && all(staleTrace.StaleFeedbackIgnored==1) && ...
    ~any(staleTrace.HARQFeedbackApplied) && ~any(staleTrace.RuntimeStateUpdated) && ...
    ~any(staleTrace.StateChangeApplied) && ~any(staleTrace.ControlStateChanged) && ...
    all(staleTrace.PUCCHGrantState=="pusch_uci_stale_feedback_ignored"));
canonicalStale=sixgr.truth.CoupledTruthRuntime.canonicalizePersistedPUCCHGrantTraceTable(staleTrace);
assert(all(canonicalStale.ControlObservationAvailable) && all(canonicalStale.FinalizedFlag) && ...
    ~any(canonicalStale.StateChangeApplied) && ~any(canonicalStale.RuntimeStateUpdated) && ...
    all(canonicalStale.RuntimeMaterializationStatus=="active_integrated_pusch_uci_feedback_runtime") && ...
    all(canonicalStale.RuntimeStateConsumer=="HARQEntity.stale_feedback_guard") && ...
    all(canonicalStale.ValueSource=="runtime_pusch_uci_feedback_trace") && ...
    ~canonicalStale.FalseAck(1) && canonicalStale.FalseAck(2), ...
    'Stale received UCI stays observed/finalized with scoring intact, not pending or state-applied.');
unknown=staleTrace;
unknown.HARQFeedbackApplied(:)=NaN; unknown.StaleFeedbackIgnored(:)=NaN;
unknown=sixgr.truth.CoupledTruthRuntime.canonicalizePersistedPUCCHGrantTraceTable(unknown);
assert(~any(unknown.ControlObservationAvailable) && ~any(unknown.FinalizedFlag), ...
    'An unknown disposition must not create a received observation.');
state = sixgr.truth.CoupledTruthRuntime. ...
    applyDecodedPUSCHHARQACKRuntime(state, harqOut);
assert(all(state.PendingFeedbackTable.Processed), ...
    "PUSCH-decoded HARQ-ACK must close every exact pending feedback row.");
assert(double(state.DLHarq.Stats.Ack) == 2 && ...
    double(state.DLHarq.Stats.Nack) == 0, ...
    ["The DL HARQ entity must consume receiver-decoded bits. The second " ...
    "false ACK proves expected bits were not substituted."]);
assert(all(cellfun(@isempty, state.DLCombinedLLR(1, 1:2))), ...
    "Observed ACKs must clear the matching DL soft buffers.");
traceT = state.PUCCHGrantTraceTable;
assert(all(traceT.PUSCHUCIDecodeOk) && all(traceT.CurrentDecodeOK) && all(traceT.CombinedDecodeOK) && ...
    isequal(logical(traceT.UCIContentMatch(:)),[true;false]), ...
    'A usable false ACK remains decoded; only scoring agreement is false.');
assert(~any(traceT.GrantExecutedFlag) && ~any(traceT.PUCCHDecodeOk) && ...
    all(traceT.RuntimeStateUpdated) && all(traceT.MultiplexedOnPUSCH), ...
    "PUSCH UCI consumption must not be mislabeled as a PUCCH waveform execution.");
assert(string(traceT.Status(1)) == "PASS" && string(traceT.Status(2)) == "FAIL" && ...
    ~logical(traceT.FalseAck(1)) && logical(traceT.FalseAck(2)) && ...
    all(string(traceT.RuntimeStateConsumer) == ...
    "HARQEntity.onFeedback_from_PUSCH_UCI"), ...
    "Transferred UCI evidence must expose exact match and false-ACK outcomes per bit.");

% Reproduce UL HARQ grant-snapshot reuse.  The retransmission grant carries
% the previous occasion's transient UCI fields, but a new DL feedback row is
% due on the new occasion.  Production must discard the stale binding and
% bind the new grant identity; replaying the already processed ACK is a
% causal runtime error.
nextDueSlot = dueSlot + 2;
nextFeedback = feedbackRows(1);
nextFeedback.SourceSlot = dueSlot + 1;
nextFeedback.DueSlot = nextDueSlot;
nextFeedback.HarqID = 2;
nextFeedback.Ack = true;
nextFeedback.CurrentDecodeOK = true;
nextFeedback.CombinedDecodeOK = true;
nextFeedback.PUCCHGrantId = "PUCCH-GRANT-REUSED-NEXT";
nextFeedback.DeliveryMechanism = "pucch";
nextFeedback.PUSCHGrantContextId = "";
nextFeedback.MultiplexedBitIndex = NaN;
nextFeedback.Processed = false;
state.PendingFeedbackTable = [state.PendingFeedbackTable; ...
    struct2table(nextFeedback, "AsArray", true)];
state = sixgr.truth.CoupledTruthRuntime.schedulePUCCHGrantRuntime( ...
    state, state.PendingFeedbackTable(end, :));
staleReusedGrant = puschGrant;
staleReusedGrant.Slot = nextDueSlot;
staleReusedGrant.ScheduledAbsoluteSlot = nextDueSlot;
staleReusedGrant.GrantContextId = "UL-PUSCH-UCI-REUSED-7";
