function ok = testPDSCHFadingHighRank()
%TESTPDSCHFADINGHIGHRANK Guard multiport CDM estimation and high-rank RX.

setup6GRSimToolkit("Verbose",false,"RunToolboxChecks",false);

carrier = nrCarrierConfig;
carrier.NCellID = 42;
carrier.NSizeGrid = 12;
carrier.SubcarrierSpacing = 60;
pdsch = nrPDSCHConfig;
pdsch.PRBSet = 0:5;
pdsch.SymbolAllocation = [0 14];
pdsch.MappingType = "A";
pdsch.Modulation = "QPSK";
pdsch.NumLayers = 3;
pdsch.DMRS.DMRSConfigurationType = 1;
pdsch.DMRS.DMRSTypeAPosition = 2;
pdsch.DMRS.DMRSAdditionalPosition = 3;
pdsch.DMRS.DMRSLength = 1;
pdsch.DMRS.NumCDMGroupsWithoutData = 2;
pdsch.DMRS.DMRSPortSet = 0:2;
[~,~,dmrsInfo] = sixgr.phy.refsig.dmrsPDSCH(carrier,pdsch);
assert(isequal(double(dmrsInfo.CDMLengths),[2 1]), ...
    ["R2026a multiport PDSCH DM-RS must preserve the authoritative " ...
    "CDMLengths=[2 1] contract."]);

rank3 = sixgr.pdsch.PDSCHCoverageExecutor.runReceiverTruthPoint( ...
    "CDL-C","Rank",3,"Modulation","QPSK", ...
    "SNRdB",65,"Seed",47,"NumTrials",1, ...
    "NumerologyKHz",60,"MappingType","A", ...
    "DMRSConfigurationType",1,"DMRSLength",1, ...
    "DMRSAdditionalPosition",3,"DMRSMultiplexing","basic", ...
    "DMRSPortSet",0:2,"PTRSEnabled",false, ...
    "PrecodingMode","prg_codebook", ...
    "ExecutionLabel","high-rank-cdl-r3");
rank6 = sixgr.pdsch.PDSCHCoverageExecutor.runReceiverTruthPoint( ...
    "CDL-C","Rank",6,"Modulation","16QAM", ...
    "SNRdB",65,"Seed",47,"NumTrials",1, ...
    "NumerologyKHz",30,"MappingType","A", ...
    "DMRSConfigurationType",2,"DMRSLength",1, ...
    "DMRSAdditionalPosition",2,"DMRSMultiplexing","basic", ...
    "DMRSPortSet",0:5,"PTRSEnabled",false, ...
    "PrecodingMode","prg_noncodebook", ...
    "ExecutionLabel","high-rank-cdl-r6");

for probe = {rank3,rank6}
    value = probe{1};
    assert(value.Passed && value.TBErrors == 0, ...
        "High-rank fading production RX failed TB recovery.");
    assert(contains(value.ChannelEstimateScope,"resource_selective"), ...
        "High-rank fading RX must expose a resource-selective estimate.");
    assert(~contains(lower(value.ChannelEstimateSource), ...
        ["scalar","fallback","proxy","unit_channel"]), ...
        "High-rank fading evidence contains a prohibited estimate source.");
    assert(all(logical(value.TrialTable.StrictReceiverEvidenceOk)) ...
        && all(logical(value.TrialTable.LLRFinite)), ...
        "High-rank fading production-stage evidence is incomplete.");
    assert(string(value.ExecutionBackend) == ...
        "PDSCHTransmitter>38.901_channel>PDSCHReceiver" ...
        && all(string(value.TrialTable.ExecutionBackend) == ...
            value.ExecutionBackend) ...
        && all(string(value.TrialTable.ChannelObjectClass) == ...
            "nrCDLChannel") ...
        && all(string(value.TrialTable.ChannelEstimateSource) == ...
            "nrChannelEstimate"), ...
        "High-rank fading evidence is not one canonical end-to-end execution.");
    hScope = string(value.TrialTable.ChannelEstimateScope);
    assert(all(contains(hScope,"resource_selective")) ...
        && all(isfinite(value.TrialTable.NMSE_dB)), ...
        "High-rank fading lacks finite per-resource DM-RS estimator evidence.");
end

fprintf("PDSCH high-rank fading: rank3 SINR %.2f dB, rank6 SINR %.2f dB\n", ...
    rank3.MeasuredSINRdB,rank6.MeasuredSINRdB);
ok = true;
end
