function ok = testSupplementalEvidenceScopeClassification()
%TESTSUPPLEMENTALEVIDENCESCOPECLASSIFICATION Component qualification cannot certify in-path truth.

setup6GRSimToolkit("Verbose", false);
stats = struct("PRACHRequired", true, "PRACHStrictOk", false, ...
    "PRACHStatus", "missing_strict_prach_config_or_trials");
anchor = struct("StrictOk", true, "Ok", true, ...
    "StatisticallyQualified", true, "StatisticalQualification", "PASS", ...
    "EvidenceScope", "component_anchor", ...
    "SameScenarioInPathEligible", false, ...
    "ArtifactRoot", "component_anchors/prach", "FailureReason", "");
result = struct("StrictSupplemental", struct("PRACH", anchor));

classified = sixgr.truth.classifySupplementalEvidenceScope( ...
    stats, result, "PRACH", "PRACHStatus");
assert(~logical(classified.PRACHStrictOk), ...
    "A passing component anchor must not promote the in-path PRACH gate.");
assert(logical(classified.ComponentAnchorStrictOk) && ...
    logical(classified.ComponentAnchorStatisticallyQualified));
assert(string(classified.ComponentAnchorStatus) == ...
    "PASS_NOT_SAME_SCENARIO_IN_PATH");
assert(contains(string(classified.PRACHStatus), ...
    "component_anchor_pass_not_same_scenario_in_path"));

badScope = anchor;
badScope.EvidenceScope = "";
result.StrictSupplemental.PRACH = badScope;
classifiedBad = sixgr.truth.classifySupplementalEvidenceScope( ...
    stats, result, "PRACH", "PRACHStatus");
assert(~logical(classifiedBad.PRACHStrictOk));
assert(string(classifiedBad.ComponentAnchorStatus) == ...
    "INVALID_OR_UNTYPED_SCOPE");

ok = true;
end
