function ok = testDLMCSCQIConsistencyGate()
setup6GRSimToolkit("Verbose", false);
runFolder = tempname;
mkdir(fullfile(runFolder, "packet_flow", "csv"));
c = onCleanup(@() rmdir(runFolder, "s")); %#ok<NASGU>

grants = localGrantRows();
writetable(grants, fullfile(runFolder, "packet_flow", "csv", "live_dl_scheduler_grants.csv"));

scfg = struct();
scfg.ScenarioID = "dl_mcs_cqi_consistency_gate_unit";
scfg.ConfigHash = "unit";
scfg.simulation.random_seed = 240619;
scfg.frequency.center_frequency_hz = 4e9;
scfg.frequency.bandwidth_hz = 100e6;
scfg.frame.scs_khz = 30;
cfg = struct();
cfg.run.runTag = "dl_mcs_cqi_consistency_gate_unit";
cfg.frequency.center_frequency_hz = 4e9;
cfg.frequency.bandwidth_hz = 100e6;

sixgr.truth.exportLLSOutputCoverageArtifacts(runFolder, scfg, cfg);
registryPath = fullfile(runFolder, "reports", "csv", "result_issue_registry.csv");
assert(exist(registryPath, "file") == 2, "Result issue registry must be exported.");
registry = readtable(registryPath, "TextType", "string");
ids = string(registry.issue_id);

assert(~any(ids == "dl_mcs_above_cqi_1"), ...
    "Stateful measured-feedback DL link adaptation must not be flagged as raw CQI over-selection.");
assert(any(ids == "dl_mcs_above_cqi_2"), ...
    "Unsourced CQI-table DL MCS above the 38.214 CQI/MCS spectral-efficiency bound must be flagged.");

row = registry(ids == "dl_mcs_above_cqi_2", :);
assert(contains(string(row.observed_value(1)), "SelectedSE="), ...
    "MCS/CQI issue evidence must disclose 38.214 spectral-efficiency comparison details.");
ok = true;
end

