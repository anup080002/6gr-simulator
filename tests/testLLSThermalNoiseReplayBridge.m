function ok = testLLSThermalNoiseReplayBridge()
%TESTLLSTHERMALNOISEREPLAYBRIDGE Ensure thermal-noise replay keeps a finite SNR bridge.

setup6GRSimToolkit("Verbose", false);

scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", "variants", "SCN00_BASELINE_CAPACITY.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tempdir, "lls_thermal_noise_bridge_probe"));

fs = double(sixgr.util.structGet(cfg, "lls6g.resolvedConfig.waveform.sample_rate_hz", 122880000));
x = complex(ones(256, 1), zeros(256, 1));

cfgDL = cfg;
cfgDL = sixgr.util.structSet(cfgDL, "lls6g.userContext", struct( ...
    "RuntimeCurrentDirection", "DL", ...
    "RuntimeServingPathloss_dB", 110, ...
    "RuntimeServingShadowFading_dB", 0, ...
    "RuntimeServingO2I_dB", 0));
[~, replayDL] = sixgr.link.applyWaveformImpairments(x, cfgDL, fs);
assert(strcmpi(string(sixgr.util.structGet(replayDL, "NoiseOperatingMode", "")), "receiver_noise_figure_thermal_noise"), ...
    "SCN00 thermal-noise mode must stay active in the replay context.");
assert(isfinite(double(sixgr.util.structGet(replayDL, "ServingRxPower_dBm", NaN))), ...
    "DL thermal-noise replay must derive a finite serving receive power when runtime pathloss is present.");
assert(strcmpi(string(sixgr.util.structGet(replayDL, "ServingRxPowerSource", "")), "power_context_link_budget"), ...
    "DL thermal-noise replay must disclose the PowerContext link-budget bridge.");
assert(abs(double(sixgr.util.structGet(replayDL, "ServingRxPower_dBm", NaN)) + 64) < 1e-6, ...
    "DL derived serving receive power must match configured BS TX power minus large-scale loss.");
assert(isfinite(double(sixgr.util.structGet(replayDL, "AppliedAWGNSNR_dB", NaN))), ...
    "DL thermal-noise replay must keep a finite AWGN-equivalent SNR bridge.");

cfgUL = cfg;
cfgUL = sixgr.util.structSet(cfgUL, "lls6g.userContext", struct( ...
    "RuntimeCurrentDirection", "UL", ...
    "RuntimeServingPathloss_dB", 110, ...
    "RuntimeServingShadowFading_dB", 0, ...
    "RuntimeServingO2I_dB", 0));
[~, replayUL] = sixgr.link.applyWaveformImpairments(x, cfgUL, fs);
assert(isfinite(double(sixgr.util.structGet(replayUL, "ServingRxPower_dBm", NaN))), ...
    "UL thermal-noise replay must derive a finite serving receive power when runtime pathloss is present.");
assert(strcmpi(string(sixgr.util.structGet(replayUL, "ServingRxPowerSource", "")), "power_context_link_budget"), ...
    "UL thermal-noise replay must disclose the PowerContext link-budget bridge.");
assert(abs(double(sixgr.util.structGet(replayUL, "ServingRxPower_dBm", NaN)) + 87) < 1e-6, ...
    "UL derived serving receive power must match configured UE TX power minus large-scale loss.");
assert(isfinite(double(sixgr.util.structGet(replayUL, "AppliedAWGNSNR_dB", NaN))), ...
    "UL thermal-noise replay must keep a finite AWGN-equivalent SNR bridge.");

ok = true;
end
