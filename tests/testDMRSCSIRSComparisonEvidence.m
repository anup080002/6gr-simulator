function [ok,folder]=testDMRSCSIRSComparisonEvidence()
% Bounded native OFDM/pilot receiver + real production archive roundtrip.
% This is a component measurement, not transport, scenario, independent-
% trial qualification, or a fabricated common-plane estimator comparison.
setup6GRSimToolkit('Verbose',false);
folder=fullfile(pwd,'results','lls','dmrs_csirs_comparison_evidence', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(folder);
[dl,csirs,isolated]=producerArchives(folder);
[observations,pairs]=sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,dl,csirs);
assert(height(observations)==3 && isempty(pairs) && all(observations.NMSEAvailable));
assert(isequal(observations.Method,["PDSCH_DMRS";"CSI_RS";"CSI_RS"]) && ...
    isequal(observations.ResourceID(2:3),[1;2]) && ...
    observations.WaveformPrecoderSHA256(2)~=observations.WaveformPrecoderSHA256(3), ...
    'Different actually executed CSI-RS resource matrices must remain separate.');
assert(all(observations.PairingStatus=="incompatible_reference_plane_or_RF_scope") && ...
    all(~observations.StatisticallyQualified) && all(observations.ReferenceUsedByReceiver==0));
assert(all(observations.ReferenceRFImpairmentsIncluded==0));
assert(all(observations.ReceiverID=="component_ue") && ...
    all(observations.ReceiverClockDomain=="native_pilot_component_sample_clock") && ...
    all(observations.ReceiverClockEpoch==1));
for k=1:height(observations)
    row=observations(k,:);
    resources=sixgr.util.csvReadTable(fullfile(folder,row.ResourcesCSV),'TextType','string');
    if isfinite(row.ResourceID), resources=resources(resources.ResourceID==row.ResourceID,:); end
    estimate=complex(resources.HReal,resources.HImag);
    reference=complex(resources.ReferenceHReal,resources.ReferenceHImag);
    err=sum(abs(estimate-reference).^2); energy=sum(abs(reference).^2);
    assert(abs(row.ErrorEnergy-err)<1e-12 && abs(row.ReferenceEnergy-energy)<1e-12 && ...
        row.ComparedValues==numel(estimate) && abs(row.NMSELinear-err/energy)<1e-12 && ...
        row.Status=="independent_resource_NMSE_not_paired_comparison");
end
assert(abs(sum(observations.ErrorEnergy(2:3))-csirs.ChannelNMSEErrorEnergy)<1e-12 && ...
    abs(sum(observations.ReferenceEnergy(2:3))-csirs.ChannelNMSEReferenceEnergy)<1e-12);

% Modern RF-inclusive effective-layer reference is not CSI-port nominal H.
[rfObservations,rfPairs]=sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,isolated,csirs);
assert(height(rfObservations)==3 && isempty(rfPairs) && ...
    rfObservations.ReferenceRFImpairmentsIncluded(1)==1 && ...
    all(rfObservations.ReferenceRFImpairmentsIncluded(2:3)==0) && ...
    rfObservations.ReferencePlane(1)~=rfObservations.ReferencePlane(2) && ...
    all(rfObservations.PairingStatus=="incompatible_reference_plane_or_RF_scope"));

% Repeated source rows stay identifiable; no hidden grouping/mean subtraction.
[repeated,repeatPairs]=sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,[dl;dl],csirs);
assert(height(repeated)==4 && isempty(repeatPairs) && ...
    isequal(repeated.SourceTrialRow(1:2),[1;2]) && ...
    repeated.ObservationID(1)==repeated.ObservationID(2));
assert(repeated.NMSELinear(1)==repeated.NMSELinear(2));

% Missing actual receiver/clock identity does not erase valid independent
% operands, and a supplied RF revision/measurement epoch is not a substitute.
withoutClock=removevars(dl,{'ReceiverID','ReceiverClockDomain','ReceiverClockEpoch'});
withoutClock.RFConfigurationEpoch=41; withoutClock.MeasurementClockEpoch=42;
[unbound,unboundPairs]=sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,withoutClock,table());
assert(height(unbound)==1 && unbound.NMSEAvailable && isempty(unboundPairs) && ...
    unbound.ReceiverID=="" && unbound.ReceiverClockDomain=="" && isnan(unbound.ReceiverClockEpoch) && ...
    unbound.NMSELinear==observations.NMSELinear(1), ...
    'Independent NMSE survives absent clocks; UE/RF/measurement labels must not manufacture clock identity.');

% A scalar aggregate, stale row or a missing file cannot supply H operands.
legacy=table(1,1,20,-70,'VariableNames',{'Slot','UEIndex','ConfiguredSNR_dB','NMSE_dB'});
[missing,missingPairs]=sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,legacy,table());
assert(height(missing)==1 && isempty(missingPairs) && ~missing.NMSEAvailable && ...
    isnan(missing.NMSELinear) && isnan(missing.ErrorEnergy) && ...
    missing.Status=="unavailable_resource_archive_not_retained");
absent=dl; absent.ChannelEstimateResourcesCSV="channel_estimation/csv/no_such_capture.csv";
[missing,~]=sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,absent,table());
assert(~missing.NMSEAvailable && isnan(missing.NMSE_dB) && ...
    missing.Status=="unavailable_declared_archive_missing");
partial=removevars(dl,'ChannelEstimateMATFileSHA256');
[missing,~]=sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,partial,table());
assert(~missing.NMSEAvailable && missing.Status=="unavailable_incomplete_archive_binding");
[empty,emptyPairs]=sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,dl([],:),csirs([],:));
assert(isempty(empty) && isempty(emptyPairs));
for name=string(observations.Properties.VariableNames)
    assert(strcmp(class(empty.(name)),class(observations.(name))), ...
        'Header-only observation field %s must retain its populated type.',name);
end
assert(isstring(empty.Method) && islogical(empty.NMSEAvailable) && ...
    isa(empty.NMSELinear,'double') && isstring(emptyPairs.DMRSObservationID) && ...
    isa(emptyPairs.DeltaNMSELinear,'double') && islogical(emptyPairs.DeltaNMSEdBAvailable));
[noColumns,noColumnPairs]=sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,table(),table());
assert(isequaln(noColumns,empty) && isequaln(noColumnPairs,emptyPairs), ...
    'Missing input tables and header-only tables must produce the same typed empty schema.');

% Wrong provenance and mismatched aggregate claims fail, not unavailable->0.
bad=dl; bad.ChannelEstimateResourcesCSVSHA256=string(repmat('0',1,64));
mustFail(@()sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,bad,table()), ...
    'sixgr:report:ChannelComparisonChecksum');
bad=dl; bad.ChannelEstimateObservationID="different_actual_observation";
mustFail(@()sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,bad,table()), ...
    'sixgr:report:ChannelComparisonObservationIdentity');
bad=dl; bad.ChannelNMSEErrorEnergy=bad.ChannelNMSEErrorEnergy+1;
mustFail(@()sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,bad,table()), ...
    'sixgr:report:ChannelComparisonEnergyClosure');
bad=csirs; bad.UEIndex=2;
mustFail(@()sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,table(),bad), ...
    'sixgr:report:ChannelComparisonObservationIdentity');
bad=dl; bad.ChannelEstimateResourcesCSV="../outside.csv";
mustFail(@()sixgr.report.collectDMRSCSIRSComparisonEvidence(folder,bad,table()), ...
    'sixgr:report:ChannelComparisonRunScope');

% Roundtrip final observations; their exact numerical provenance is retained.
path=fullfile(folder,'component_channel_estimator_observations.csv');
sixgr.util.csvWriteTable(path,observations,'PreserveSchema',true,'RoundTripNumericText',true);
saved=sixgr.util.csvReadTable(path,'TextType','string');
assert(isequaln(saved.NMSELinear,observations.NMSELinear) && ...
    isequal(saved.ResourcesCSVSHA256,observations.ResourcesCSVSHA256) && ...
    isequal(saved.ReferencePlane,observations.ReferencePlane));
fprintf('DMRS_CSIRS_COMPARISON_EVIDENCE_PASS observations=%d paired_comparisons=0 scope=native_pilot_component folder=%s\n', ...
    height(observations),folder);
ok=true;
end

function [dl,csirs,isolated]=producerArchives(folder)
carrier=nrCarrierConfig('NSizeGrid',24,'SubcarrierSpacing',15);
pdsch=nrPDSCHConfig('PRBSet',0:23,'NumLayers',1);
pdsch.DMRS.DMRSPortSet=0;
dmrsIndices=nrPDSCHDMRSIndices(carrier,pdsch);
dmrsSymbols=nrPDSCHDMRS(carrier,pdsch);
K=12*carrier.NSizeGrid; L=carrier.SymbolsPerSlot;
dmrsGrid=nrResourceGrid(carrier,1); dmrsGrid(dmrsIndices)=dmrsSymbols;
Wdmrs=[1;1]/sqrt(2);
physicalGrid=reshape(reshape(dmrsGrid,[],1)*Wdmrs.',K,L,2);
events=struct([]); resources=struct([]);
for r=1:2
    signal=nrCSIRSConfig('CSIRSType','nzp','CSIRSPeriod','on','RowNumber',2, ...
        'Density','one','SymbolLocations',6+2*r,'SubcarrierLocations',0,'NumRB',24);
    indices=nrCSIRSIndices(carrier,signal); symbols=nrCSIRS(carrier,signal);
    assert(isempty(intersect(double(indices),double(dmrsIndices))), ...
        'Fixture requires actually disjoint DMRS and CSI-RS resource elements.');
    grid=nrResourceGrid(carrier,1); grid(indices)=symbols;
    W=zeros(2,1); W(r)=1;
    physicalGrid=physicalGrid+reshape(reshape(grid,[],1)*W.',K,L,2);
    events(r).ResourceID=r; %#ok<AGROW>
    events(r).WaveformPrecoderMatrix=W;
    events(r).WaveformPrecoderDigest=sixgr.phy.mimo.MatrixContract.digest(W);
    resources(r).ResourceID=r; %#ok<AGROW>
    resources(r).Indices=indices; resources(r).Symbols=symbols;
end
[transmitted,~]=nrOFDMModulate(carrier,physicalGrid,'Windowing',0);
H=[.8+.1i .2-.1i;.3+.2i .6-.3i];
clean=transmitted*H.'; % Actual fixed matrix execution, retained below.
[received,~]=sixgr.phy.waveform.addOccupiedREAWGN(clean,carrier,20, ...
    'Seed',74129,'SignalEnergyPerOccupiedRE',1);
[rxGrid,ofdm]=sixgr.phy.waveform.ofdmDemodulate(carrier,received);
estimate=nrChannelEstimate(carrier,rxGrid,dmrsIndices,dmrsSymbols,'CDMLengths',[2 1]);
operator=struct('ReceiveCombiningMatrix',eye(2),'CaptureOriginCFOCorrection_Hz',0, ...
    'AlignedOriginCFOCorrection_Hz',0,'AppliedTimingCorrection_samples',0, ...
    'SampleRateHz',ofdm.SampleRate,'TimingApplicationPolicy',"timing_estimation_bypassed_no_runtime_correction");
rx=struct('EffectiveLayerChannelEstimate',estimate,'DMRSIndices',dmrsIndices, ...
    'DMRSSymbols',dmrsSymbols,'Carrier',carrier,'PDSCH',pdsch, ...
    'ReceiverChannelOperator',operator,'OFDMInfo',ofdm);
snapshot=sixgr.phy.dl.capturePDSCHChannelEstimate(rx);
count=size(transmitted,1); fs=ofdm.SampleRate;
reference=struct('Source',"executed_fixed_matrix_AWGN_operator", ...
    'SpatialMatrix',H,'PathGains',repmat(reshape(H.',1,1,2,2),count,1,1,1), ...
    'PathFilters',1,'SampleTimes_s',(0:count-1)'/fs,'StartSample',0, ...
    'EndSampleExclusive',count,'SampleRateHz',fs,'StateKey',"native_component_fixed_operator", ...
    'NumTransmitAntennas',2,'NumReceiveAntennas',2, ...
    'NormalizeChannelOutputs',false,'NormalizePathGains',false, ...
    'ReceiverEstimatorInput',false,'AdditionalChannelExecutions',0);
captures={struct('Reference',reference,'LinkID',"component_dl", ...
    'TX',"component_gnb",'RX',"component_ue",'AppliedLargeScaleAmplitudeGain',1)};
base=table(1,1,1,20,1,74129,74129,0,fs,count, ...
    'VariableNames',{'Slot','UEIndex','CellID','ConfiguredSNR_dB','SweepPointIndex', ...
    'Seed','RandomSeed','ObservationStartSample','ObservationSampleRateHz','ObservationEndSampleExclusive'});
base.ReceiverClockEpoch=1;
base.ReceiverID="component_ue"; base.ReceiverClockDomain="native_pilot_component_sample_clock";
base.RunID=string(folder); base.ExecutionID="native_pilot_component_execution";
base.ConfigHash="native_pilot_component_not_a_scenario_configuration";
base.ChannelObservationID="native_pilot_component_dmrs_observation";
prepared=struct('Direction',"DL",'SampleRateHz',fs,'ReceiveStartSample',0,'StartSample',0, ...
    'Tx',struct('Carrier',carrier,'Waveform',transmitted, ...
    'PrecodeInfo',struct('MatrixPorts',Wdmrs),'PowerContext',struct('AmplitudeScale',1)));
dl=sixgr.truth.exportSharedDataChannelEstimate(folder,base,snapshot,prepared, ...
    captures,{struct('AppliedLargeScaleGain_dB',0)},eye(2));

replay=struct('TimingOffsetApplied',false,'InjectedTimingOffset_samples',0, ...
    'CFOApplied',false,'InjectedCFO_Hz',0,'RFEndpoint',"rx",'RFStageOrder',"rx_timing>rx_lo_cfo");
cfg=struct('channel',struct('model','AWGN'),'run',struct('rootRunFolder',folder));
context=struct('Slot',1,'UEIndex',1,'ConfiguredSNR_dB',20);
scored=sixgr.link.scoreIsolatedDataChannelEstimate(rx,clean,cfg,"DL",context,replay);
isolated=base;
for name=string(fieldnames(scored)).', isolated.(name)=scored.(name); end

measurements=struct([]);
for r=1:2
    h=nrChannelEstimate(carrier,rxGrid,resources(r).Indices,resources(r).Symbols);
    measurements(r).ResourceID=r; measurements(r).Available=true; %#ok<AGROW>
    measurements(r).Hest=h;
end
rxCSI=struct('ReceiverOFDMInfo',ofdm,'RxGrid',rxGrid, ...
    'ReceiverTrackingCorrection',struct('CFOCorrectionApplied',false), ...
    'ReceiveTiming',struct('AppliedTimingCorrectionSamples',0), ...
    'CSIRSInfo',struct('Resources',resources),'CSIRSChannelEstimate',measurements(1).Hest, ...
    'CSIChannelEstimateSource',"actual_native_nrChannelEstimate_component", ...
    'CSIRSChannelEstimation',struct('Available',true,'ResourceMeasurements',measurements,'SelectedResourceOrdinal',1));
preparedCSI=struct('ExecutionStage',"csirs_waveform_prepared_not_received", ...
    'SampleRateHz',fs,'Carrier',carrier,'NumPhysicalTransmitAntennas',2, ...
    'RuntimeSlot',1,'RequestedSNR_dB',20,'ReceiveStartSample',0,'TransmitStartSample',0, ...
    'ReceiverConfig',struct('lls6g',struct('userContext',struct('RuntimeUEIndex',1))), ...
    'PowerContext',struct('AmplitudeScale',1), ...
    'Tx',struct('CSIRSRuntimeEvent',struct('ResourceEvents',events)));
source=struct('Source',"actual_executed_link_contribution",'LinkID',"component_dl", ...
    'TransmitterID',"component_gnb",'ReceiverID',"component_ue", ...
    'ReceiverEstimatorInput',false,'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0, ...
    'ChannelReferenceCoverageComplete',true, ...
    'ReceiverClockExecution',struct('ReceiveStreamExecutionSegments', ...
    {{struct('Execution',struct('RX',struct('ID',"component_ue",'Replay',replay)))}}));
csirs=sixgr.truth.exportSharedCSIRSChannelEstimate(folder,base,preparedCSI,rxCSI,source,captures);
end

function mustFail(action,expected)
caught=false;
try, action();
catch ex
    assert(strcmp(ex.identifier,expected),'Expected %s, received %s: %s',expected,ex.identifier,ex.message);
    caught=true;
end
assert(caught,'Expected evidence rejection %s.',expected);
end
