function ok = testKPIScenarioTotalBindings()
%TESTKPISCENARIOTOTALBINDINGS Mandatory totals must bind to raw trial bits.

setup6GRSimToolkit("Verbose",false);
raw = struct();
raw.UL = localDirectionTable("UL",[1000;1200],[true;false]);
raw.DL = localDirectionTable("DL",[1400;1600],[true;true]);
out = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw,"StrictMode",true);

names = ["Scenario_Total_UL_DeliveredBits"; ...
    "Scenario_Total_DL_DeliveredBits"; ...
    "Scenario_Total_UL_ScheduledBits"; ...
    "Scenario_Total_DL_ScheduledBits"];
binding = out.ObjectiveBinding(ismember(string(out.ObjectiveBinding.KPIName),names),:);
assert(height(binding) == 4 && all(logical(binding.MandatoryInScenarioObjective)), ...
    "All four scenario bit totals must be present as mandatory objective bindings.");
assert(all(logical(binding.RawEvidenceAvailable)) && ...
    all(logical(binding.ReconstructionPass)) && ...
    all(logical(binding.StrictOk)) && ...
    all(string(binding.Status) == "pass"), ...
    "Mandatory scheduled/delivered bit totals must not be classified not_applicable.");

recon = out.ReconstructionSummary;
assert(localValue(recon,"Scenario_Total_UL_DeliveredBits") == 1000);
assert(localValue(recon,"Scenario_Total_DL_DeliveredBits") == 3000);
assert(localValue(recon,"Scenario_Total_UL_ScheduledBits") == 2200);
assert(localValue(recon,"Scenario_Total_DL_ScheduledBits") == 3000);

% Invalid application-delivery provenance must fail the application KPI
% only. It must never poison PHY scheduled/delivered totals that remain
% reconstructable from the same raw PUSCH/PDSCH rows.
raw.ApplicationPackets = table(["UL";"DL"], ["ul_app_1";"dl_app_1"], ...
    [true;true], [false;false], [1000;1400], ...
    'VariableNames', {'Direction','PacketId','DeliverySuccess', ...
    'SameWaveformProtocolComplete','DeliveredBits'});
outInvalidApp = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw, ...
    "StrictMode", true);
bindingInvalidApp = outInvalidApp.ObjectiveBinding(ismember( ...
    string(outInvalidApp.ObjectiveBinding.KPIName), names), :);
assert(height(bindingInvalidApp) == 4 && ...
    all(logical(bindingInvalidApp.StrictOk)) && ...
    all(string(bindingInvalidApp.Status) == "pass"), ...
    "Invalid application provenance must not invalidate same-chain PHY totals.");
applicationRows = outInvalidApp.ReconstructionSummary(contains( ...
    string(outInvalidApp.ReconstructionSummary.KPIName), ...
    "Application_Goodput_Mbps"), :);
manifest=outInvalidApp.SourceManifest(outInvalidApp.SourceManifest.Direction=="ApplicationPackets",:);
for direction=["DL","UL"]
    subset=raw.ApplicationPackets(raw.ApplicationPackets.Direction==direction,:);
    assert(manifest.(direction+"SubsetRowCount")==height(subset) && ...
        manifest.(direction+"SubsetRowsHash")==sixgr.kpi.hashKPISourceRows(subset), ...
        'Packet manifests must bind the exact directional population, even when delivery is invalid.');
end
assert(~outInvalidApp.StrictOk && all(~logical(applicationRows.StrictOk)) && ...
    all(contains(string(applicationRows.FailureReason), ...
    "application_delivery_claim_not_backed")), ...
    "Application KPI must still fail closed on incomplete protocol provenance.");

outProtocolDisabled = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw, ...
    "StrictMode", true, "FeatureApplicability", struct( ...
    "HARQ", true, "Scheduler", true, "Latency", true, ...
    "MAC", false, "Application", false));
disabledApplicationRows = outProtocolDisabled.ReconstructionSummary(contains( ...
    string(outProtocolDisabled.ReconstructionSummary.KPIName), ...
    "Application_Goodput_Mbps"), :);
assert(~isempty(disabledApplicationRows) && ...
    all(string(disabledApplicationRows.Status) == "not_applicable") && ...
    all(string(disabledApplicationRows.ApplicabilityReason) == ...
    "same_waveform_protocol_stack_disabled"), ...
    "Configuration-disabled protocol KPIs must be explicitly not applicable, not falsely passed or failed.");
ok = true;
end

function value = localValue(T,name)
row = T(strcmp(string(T.KPIName),name),:);
assert(height(row) == 1);
value = double(row.ReconstructionValue(1));
end

function T = localDirectionTable(direction,tbBits,crcPass)
n = numel(tbBits);
goodBits = double(tbBits).*double(crcPass);
T = table(repmat(string(direction),n,1),goodBits/1000,logical(crcPass), ...
    double(~crcPass),ones(n,1),double(tbBits),goodBits,ones(n,1), ...
    (1:n).',string(direction)+"_tb_"+string((1:n).'),zeros(n,1), ...
    zeros(n,1),zeros(n,1),ones(n,1),(1:n).', ...
    'VariableNames',{'Direction','Goodput_Mbps','CRCPass','BitErrors', ...
    'BitsCompared','TBSize_bits','GoodBits','Frame','Slot', ...
    'TransportBlockId','HARQProcessId','RV','NDI', ...
    'AirInterfaceObservation_ms','TrialId'});
end
