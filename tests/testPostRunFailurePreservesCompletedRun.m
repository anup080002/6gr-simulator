function testPostRunFailurePreservesCompletedRun()
setup6GRSimToolkit('Verbose', false, 'RunToolboxChecks', false);

completed = struct( ...
    'RunCompletion', "completed", ...
    'ResultOk', true, ...
    'RuntimeTruthContractOk', true, ...
    'RequiredFailureCount', 0, ...
    'StrictTruthFailureCount', 0, ...
    'StrictProxyGuardFailureCount', 0);
assert(sixgr.lls6g.runners.shouldPreserveCompletedRunOnPostRunFailure(completed), ...
    'Late post-run failures must preserve a completed truth-backed run.');

failedTruth = completed;
failedTruth.RuntimeTruthContractOk = false;
assert(~sixgr.lls6g.runners.shouldPreserveCompletedRunOnPostRunFailure(failedTruth), ...
    'Runs without a green truth contract must not be preserved as completed.');

requiredFailure = completed;
requiredFailure.RequiredFailureCount = 1;
assert(~sixgr.lls6g.runners.shouldPreserveCompletedRunOnPostRunFailure(requiredFailure), ...
    'Runs with required failures must not be preserved as completed.');

incomplete = completed;
incomplete.RunCompletion = "failed";
assert(~sixgr.lls6g.runners.shouldPreserveCompletedRunOnPostRunFailure(incomplete), ...
    'Failed runs must still enter the failed-run recovery path.');
end
