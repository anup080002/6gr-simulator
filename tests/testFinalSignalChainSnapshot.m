function ok=testFinalSignalChainSnapshot()
% Declared publication fixture, not PHY samples or performance evidence.
% Final snapshots preserve every point; normal live polling remains bounded.
folder=tempname(fullfile(pwd,'logs'));
count=5000;
wave=table((1:count).',repelem([40;30;20;10;0;-10;-20;-30],625), ...
    repmat("declared_publication_unit_fixture",count,1), ...
    'VariableNames',{'SampleIndex','SNR_dB','Source'});
live=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'live'), ...
    table(),table(),struct('WaveformPreviewTable',wave));
assert(height(live.WaveformPreview)==4096 && live.WaveformPreview.SampleIndex(1)==905);
final=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'final'), ...
    table(),table(),struct('WaveformPreviewTable',wave,'FinalSnapshot',true));
saved=sixgr.util.csvReadTable(final.WaveformPreviewPath,'TextType','string');
assert(isequaln(final.WaveformPreview,wave) && isequaln(saved,wave), ...
    'test:FinalPreviewTruncated','Final publication must retain all eight points exactly.');
assert(isempty(final.ModulationTrace) && isempty(final.ChannelEstimationTrace), ...
    'No primary PHY trial evidence may be manufactured from a preview.');
% Receiver measurements must become visible before a heavy plot milestone,
% without clearing the retained waveform samples. These are declared table
% fixtures, not newly simulated PHY evidence.
previewBytes=fileread(live.WaveformPreviewPath);
trial=table("DL",40,2,41,1,1,15.25,"PASS", ...
    'VariableNames',{'Direction','SNR_dB','Frame','Slot','UEID','Layers','PostEqSINR_dB','Status'});
updated=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'live'), ...
    trial,table(),struct('WriteWaveformPreview',false));
assert(strcmp(fileread(live.WaveformPreviewPath),previewBytes), ...
    'A compact receiver refresh must not erase or replace retained waveform samples.');
assert(height(updated.ChannelStateTrace)==1 && updated.ChannelStateTrace.Slot==41 && ...
    updated.ChannelStateTrace.PostEqSINR_dB==15.25 && height(updated.ChannelEstimationTrace)==1);
persisted=sixgr.util.csvReadTable(updated.ChannelStateTracePath,'TextType','string');
assert(height(persisted)==1 && persisted.Slot==41 && persisted.PostEqSINR_dB==15.25);
source=fileread(which('sixgr.truth.runWaveformLinkBundle'));
begin=strfind(source,'function liveArtifacts = localPublishCoupledTruthRuntimeState');
stop=strfind(source,'function '); stop=stop(stop>begin(1));
publisher=source(begin(1):stop(1)-1);
assert(contains(publisher,'if refreshHeavyArtifacts || writeRawTablesNow') && ...
    contains(publisher,'"WriteWaveformPreview",refreshHeavyArtifacts'), ...
    'The production publisher must update compact receiver tables with primary trials.');
% Reused slot/sample coordinates are not shared UE or sweep identities.
% These tables are serialization fixtures only, not simulated PHY captures.
trial=table(repmat("DL",3,1),[40;40;40],[2;2;2],[41;41;41], ...
    [1;2;1],[1;1;2],[101;101;102], ...
    'VariableNames',{'Direction','SNR_dB','Frame','Slot','UEIndex','SweepPointIndex','Seed'});
samples=trial([1;1;2;2;2;3;3;3;3],:);
counted=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'identity'), ...
    trial,samples,struct('FinalSnapshot',true));
assert(isequal(counted.ModulationTrace.ConstellationSamples,[2;3;4]), ...
    'test:ConstellationSampleOwnership','Sample counts must be UE and sweep scoped.');
assert(isequal(counted.ModulationTrace.SweepPointIndex,trial.SweepPointIndex) && ...
    isequal(counted.ModulationTrace.Seed,trial.Seed));
assert(all(counted.ModulationTrace.ConstellationSampleCountScope=="retained_input_rows_not_full_capture_coverage"));
% Same coordinates are insufficient for two distinct physical attempts.
attemptTrial=trial([1;1],:);
attemptTrial.TransmissionAttemptID=["attempt_a";"attempt_b"];
attemptSamples=attemptTrial([1;2;2],:);
attempt=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'attempt'), ...
    attemptTrial,attemptSamples,struct('FinalSnapshot',true));
assert(isequal(attempt.ModulationTrace.ConstellationSamples,[1;2]));
partialSamples=attemptSamples;
partialSamples.TransmissionAttemptID(2)="";
partial=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'partial_identity'), ...
    attemptTrial,partialSamples,struct('FinalSnapshot',true));
assert(all(isnan(partial.ModulationTrace.ConstellationSamples)), ...
    'An unidentified captured attempt must not become a measured zero count.');
attemptSamples.TransmissionAttemptID=[];
ambiguous=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'ambiguous'), ...
    attemptTrial,attemptSamples,struct('FinalSnapshot',true));
assert(all(isnan(ambiguous.ModulationTrace.ConstellationSamples)), ...
    'A missing attempt identity cannot assign the same samples to both trials.');
unknownSamples=removevars(samples,'UEIndex');
unknown=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'unknown'), ...
    trial,unknownSamples,struct('FinalSnapshot',true));
assert(all(isnan(unknown.ModulationTrace.ConstellationSamples)), ...
    'Missing UE identity must not be replaced by an all-user sample count.');
% An absent optional field is not a measured discriminator. All-missing
% legacy columns are harmless; two source-only attempt IDs are ambiguous.
legacyTrial=removevars(trial(1,:),{'SweepPointIndex','Seed'});
legacySamples=repmat(legacyTrial,3,1);
legacySamples.Seed=nan(3,1);
legacy=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'legacy'), ...
    legacyTrial,legacySamples,struct('FinalSnapshot',true));
assert(legacy.ModulationTrace.ConstellationSamples==3);
missingAttempt=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'source_attempts'), ...
    removevars(attemptTrial(1,:),'TransmissionAttemptID'), ...
    attemptTrial,struct('FinalSnapshot',true));
assert(isnan(missingAttempt.ModulationTrace.ConstellationSamples));
manySamples=repmat(trial(1,:),5000,1);
bounded=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'bounded_count'), ...
    trial(1,:),manySamples,struct());
complete=sixgr.truth.exportLLSLiveSignalChainTables(fullfile(folder,'complete_count'), ...
    trial(1,:),manySamples,struct('FinalSnapshot',true));
assert(bounded.ModulationTrace.ConstellationSamples==4096 && ...
    complete.ModulationTrace.ConstellationSamples==5000, ...
    'Retained preview counts must not claim to be the full receiver population.');
fprintf('FINAL_SIGNAL_SNAPSHOT_PASS final_rows=%d live_rows=4096 folder=%s\n',count,folder);
ok=true;
end
