function ok = testHARQTBContextInvariants()
%TESTHARQTBCONTEXTINVARIANTS Immutable HARQ TB context contract tests.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
if ~localHaveRequired5G()
    error("sixgr:test:Required5GToolboxUnavailable", ...
        ["testHARQTBContextInvariants requires the 5G Toolbox APIs " ...
        "checked by localHaveRequired5G; unavailable tests cannot pass."]);
end

layout0 = localLayout(1024, 0.50, 0);
grant0 = localGrant(1024, 0.50, true, 0, "tb_ctx_a");
meta0 = localMeta(grant0, layout0, struct(), false, double(layout0.RateMatchedBitCount), 0, NaN, false);
[ctx0, status0] = sixgr.harq.validateTBContextForTransmission(meta0);
assert(string(status0.HARQContextStatus) == "new_tx_validated", ...
    "Initial TB context must validate as new transmission.");
assert(double(ctx0.TBSBits) == 1024 && string(ctx0.CodeBlockLayoutHash) == string(layout0.CodingLayoutHash), ...
    "Initial context must bind the encoder TBS and code-block layout.");

layoutNew = localLayout(2048, 0.50, 0);
grantNew = localGrant(2048, 0.50, false, 0, "tb_ctx_b");
metaNew = localMeta(grantNew, layoutNew, ctx0, false, double(layoutNew.RateMatchedBitCount), 0, NaN, false);
[ctxNew, statusNew] = sixgr.harq.validateTBContextForTransmission(metaNew);
assert(string(statusNew.HARQContextStatus) == "new_tx_ndi_toggle_validated", ...
    "NDI toggle with previous context must validate as a fresh TB.");
assert(double(ctxNew.TBSBits) == 2048 && string(ctxNew.CodeBlockLayoutHash) == string(layoutNew.CodingLayoutHash), ...
    "NDI-toggle context must not inherit previous TBS or layout.");

grantRetx = localGrant(1024, 0.50, true, 2, "tb_ctx_a");
metaRetx = localMeta(grantRetx, layout0, ctx0, true, double(layout0.RateMatchedBitCount), 2, 0, true);
[ctxRetx, statusRetx] = sixgr.harq.validateTBContextForTransmission(metaRetx);
assert(string(statusRetx.HARQContextStatus) == "retransmission_validated", ...
    "Same-TB retransmission must validate.");
assert(double(ctxRetx.TBSBits) == double(ctx0.TBSBits), ...
    "Retransmission must preserve original TBS.");

badLayout = layout0;
badLayout.CodingLayoutHash = "different_code_block_layout";
badLayout.CombineSignature = "different_code_block_layout";
metaBadLayout = localMeta(grantRetx, badLayout, ctx0, true, double(badLayout.RateMatchedBitCount), 2, 0, true);
localAssertThrows(@() sixgr.harq.validateTBContextForTransmission(metaBadLayout), ...
    "sixgr:harq:CodeBlockLayoutMismatch");

metaShortIR = localMeta(grantRetx, layout0, ctx0, true, 512, 2, 0, false);
localAssertThrows(@() sixgr.harq.validateTBContextForTransmission(metaShortIR), ...
    "sixgr:harq:ShortIRRequiresSoftCombiningEvidence");

% Exercise the initial-code-rate failure itself.  This protects the scalar
% diagnostic contract so a malformed error message cannot mask the actual
% TBS/rate-matching tuple during a production waveform run.
badRateLayout = localLayout(1024, 0.50, 0);
badRateGrant = localGrant(1024, 0.50, true, 0, "tb_ctx_bad_rate");
badRateGrant.CodedBitCountG = 960;
metaBadRate = localMeta(badRateGrant, badRateLayout, struct(), false, 960, 0, NaN, false);
localAssertThrowsWithMessage( ...
    @() sixgr.harq.validateTBContextForTransmission(metaBadRate), ...
    "sixgr:harq:BadInitialCodeRate", ...
    ["TBSBits=1024", "rateMatchedBits=960", "MCS=10", ...
     "modulation=QPSK", "layers=1", "targetCodeRate=0.500000"]);

ok = true;
end

function meta = localMeta(grant, layout, previous, isRetx, rateMatchedBits, rv, previousRV, softEvidence)
meta = struct( ...
    "Direction", "DL", ...
    "CellId", 1, ...
    "UeId", 1, ...
    "RNTI", 101, ...
    "HARQProcessId", 0, ...
    "NDIEpoch", double(sixgr.util.structGet(grant, "HARQ.NDIEpoch", 1)), ...
    "NDI", logical(sixgr.util.structGet(grant, "HARQ.NDI", true)), ...
    "Grant", grant, ...
    "CodingLayout", layout, ...
    "PreviousContext", previous, ...
    "TransportBlockContext", previous, ...
    "IsRetransmission", logical(isRetx), ...
    "RateMatchedBitsTotal", double(rateMatchedBits), ...
    "RateMatchedBitsPerCB", double(layout.E_r), ...
    "TBSBits", double(layout.TransportBlockSize), ...
    "ExpectedTBSBits", double(layout.TransportBlockSize), ...
    "RV", double(rv), ...
    "PreviousRV", double(previousRV), ...
    "RVSequence", [0 2 3 1], ...
    "SoftCombiningEvidenceAvailable", logical(softEvidence), ...
    "PreviousCombinedLLRAvailable", logical(softEvidence));
end

function grant = localGrant(tbsBits, targetCodeRate, ndi, rv, tbId)
grant = struct();
grant.Direction = "DL";
grant.CellId = 1;
grant.ServingCell = 1;
grant.UEIndex = 1;
grant.RNTI = 101;
grant.HARQ = struct( ...
    "HarqID", 0, ...
    "HARQProcess", 0, ...
    "NDI", logical(ndi), ...
    "NDIEpoch", double(1 + ~logical(ndi)), ...
    "RV", double(rv), ...
    "IsRetransmission", logical(rv ~= 0));
grant.TransportBlockId = char(string(tbId));
grant.TBId = char(string(tbId));
grant.Codeword = 0;
grant.CodewordIndex = 0;
grant.TBSBits = double(tbsBits);
grant.TransportBlockSize = double(tbsBits);
grant.TargetCodeRate = double(targetCodeRate);
grant.MCSIndex = 10;
grant.Modulation = "QPSK";
grant.NumLayers = 1;
grant.PRBSet = 0:23;
grant.SymbolAllocation = [2 12];
grant.MappingType = "A";
grant.NREPerPRB = 120;
grant.CodedBitCountG = double(localLayout(tbsBits, targetCodeRate, rv).RateMatchedBitCount);
end

function layout = localLayout(tbsBits, targetCodeRate, rv)
qm = 2;
nLayers = 1;
E = ceil((double(tbsBits) + 24) / double(targetCodeRate));
quantum = qm * nLayers;
E = max(quantum, ceil(E / quantum) * quantum);
layout = sixgr.phy.phycode.resolveCodingLayout( ...
    "Direction", "DL", ...
    "TransportBlockSize", double(tbsBits), ...
    "TargetCodeRate", double(targetCodeRate), ...
    "RV", double(rv), ...
    "Modulation", "QPSK", ...
    "NumLayers", nLayers, ...
    "RateMatchedBitCount", double(E));
end

function localAssertThrows(fn, expectedId)
try
    fn();
catch ME
    assert(strcmp(string(ME.identifier), string(expectedId)), ...
        "Expected error %s, got %s.", string(expectedId), string(ME.identifier));
    return;
end
error("testHARQTBContextInvariants:ExpectedErrorMissing", ...
    "Expected error %s was not thrown.", string(expectedId));
end

function localAssertThrowsWithMessage(fn, expectedId, expectedTokens)
try
    fn();
catch ME
    assert(strcmp(string(ME.identifier), string(expectedId)), ...
        "Expected error %s, got %s.", string(expectedId), string(ME.identifier));
    message = string(ME.message);
    for i = 1:numel(expectedTokens)
        assert(contains(message, string(expectedTokens(i))), ...
            "Expected error message to contain '%s', got: %s", ...
            string(expectedTokens(i)), message);
    end
    return;
end
error("testHARQTBContextInvariants:ExpectedErrorMissing", ...
    "Expected error %s was not thrown.", string(expectedId));
end

function tf = localHaveRequired5G()
tf = exist("nrDLSCHInfo", "file") == 2 && ...
    exist("nrRateMatchLDPC", "file") == 2 && ...
    exist("nrLDPCEncode", "file") == 2;
end
