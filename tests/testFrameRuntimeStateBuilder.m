function ok = testFrameRuntimeStateBuilder()
%TESTFRAMERUNTIMESTATEBUILDER Production scenario-to-CC/BWP attachment.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "dl_4ghz_baseline.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
s = scfg.toStruct();
assert(string(s.meta.scenario_id) == "dl_4ghz_baseline", ...
    "The production-path fixture must originate from the real baseline YAML.");

% Keep this focused regression independent of PRACH waveform enumeration.
s.random_access.enabled = false;
nrb = double(s.frequency.n_size_grid);
scsKHz = double(s.frame.scs_khz);
half = floor(nrb / 2);
quarter = floor(nrb / 4);
s.bwp = struct();
s.bwp.dl = [ ...
    localBWP(0, 0, half, false, 1, 0, scsKHz, s.frame.cp_type), ...
    localBWP(1, quarter, half, true, 1, 1, scsKHz, s.frame.cp_type)];
s.bwp.ul = [ ...
    localBWP(2, 0, quarter, true, 1, 2, scsKHz, s.frame.cp_type), ...
    localBWP(3, half, quarter, false, 1, 3, scsKHz, s.frame.cp_type)];
s.tdd_timing = struct( ...
    "pdcch_to_pdsch_k0", 1, ...
    "pdcch_to_pusch_k2", 2, ...
    "dl_harq_feedback_k1", 4, ...
    "ul_grant_k2", 2, ...
    "n1_pdsch_processing_time_symbols", 10, ...
    "n2_pusch_preparation_time_symbols", 12, ...
    "capability_profile_id", "38.214-v18.8.0-cap1-dmrs-pos0-mu1");

runFolder = string(tempname);
mkdir(runFolder);
cleanup = onCleanup(@() localCleanup(runFolder)); %#ok<NASGU>
profile clear;
profile on;
profileCleanup = onCleanup(@() profile("off")); %#ok<NASGU>
cfg = sixgr.lls6g.buildInternalConfig(s, runFolder);
profile off;
profileInfo = profile("info");
functionNames = string({profileInfo.FunctionTable.CompleteName});
constructorCalls = sum([profileInfo.FunctionTable(endsWith(functionNames, ...
    ">FrameStructureEngine.FrameStructureEngine")).NumCalls]);
resolverCalls = sum([profileInfo.FunctionTable(endsWith(functionNames, ...
    ">FrameStructureEngine.resolve")).NumCalls]);
attachCalls = sum([profileInfo.FunctionTable(endsWith(functionNames, ...
    "buildInternalConfig.m>localApplyFrameStructureEngine")).NumCalls]);
assert(constructorCalls == 1 && resolverCalls == 1 && attachCalls == 1, ...
    "Production config construction must resolve the physical frame " + ...
    "exactly once, then attach that same validated engine (observed " + ...
    "constructor=%d, resolver=%d, attach=%d).", ...
    constructorCalls, resolverCalls, attachCalls);
profile clear;

assert(isfield(cfg.phy.frameStructure, "TimingContext"), ...
    "buildInternalConfig must attach the production timing context.");
context = cfg.phy.frameStructure.TimingContext;
assert(string(context.ContractVersion) == ...
    "sixgr_frame_runtime_state/v1");
assert(string(context.IndexConvention) == "zero_based");
assert(numel(context.ComponentCarriers) == 1 && ...
    context.ComponentCarriers(1).CCID == 0);
assert(context.BWPState(1).ActiveDLBWPID == 1 && ...
    context.BWPState(1).ActiveULBWPID == 2, ...
    "DL and UL active BWP identities must remain separate.");
assert(isequal(context.BWPState(1).ConfiguredDLBWPIDs, [0, 1]) && ...
    isequal(context.BWPState(1).ConfiguredULBWPIDs, [2, 3]), ...
    "The production snapshot must preserve complete configured BWP arrays.");
assert(numel(context.ComponentCarriers(1).BWPs) == 4);
encoded = jsonencode(context);
assert(strlength(string(encoded)) > 100 && ...
    contains(string(encoded), '"ComponentCarriers"'), ...
    "The attached CC/BWP runtime context must be serialization-safe.");

dl1 = localSnapshotBWP(context.ComponentCarriers(1).BWPs, 1, "DL");
ul2 = localSnapshotBWP(context.ComponentCarriers(1).BWPs, 2, "UL");
assert(isequal(double(dl1.ResourceGridDimensions), ...
    [12 * half, 14, 1]));
assert(isequal(double(ul2.ResourceGridDimensions), ...
    [12 * quarter, 14, 1]));
assert(double(dl1.CarrierSCSKHz) == scsKHz && ...
    dl1.BWPUpperEdgeOffsetHz <= dl1.CarrierUpperEdgeOffsetHz);
assert(numel(context.BWPState(1).History) == 2 && ...
    isempty(context.BWPState(1).PendingCommands));

identity = context.DefaultIdentity;
assert(identity.SchedulingCCID == 0 && identity.ScheduledCCID == 0 && ...
    identity.CarrierIndicator == 0 && identity.DLBWPID == 1 && ...
    identity.ULBWPID == 2);
policy = context.Policy;
assert(policy.PolicyID == "attached_runtime_timing_policy" && ...
    policy.CapabilityProfileID == ...
    "38.214-v18.8.0-cap1-dmrs-pos0-mu1" && ...
    policy.SelectedK0 == 1 && policy.SelectedK1 == 4 && ...
    policy.SelectedK2 == 2 && ...
    policy.ProcessingTimeReference == "PROCEDURE_SPECIFIC" && ...
    policy.N1PDSCHProcessingTimeSymbols == 10 && ...
    policy.N2PUSCHPreparationTimeSymbols == 12 && ...
    policy.K0Rows(1).Value == 1 && policy.K1Rows(1).Value == 4 && ...
    policy.K2Rows(1).Value == 2);
assert(~isfield(policy, "TimingAdvanceTicks"), ...
    "An unresolved timing advance must not be serialized as zero.");

% Reconstruct live state from the attached, serialization-safe snapshot and
% prove that switching a BWP does not rewrite global carrier/numerology.
globalNRB = double(cfg.phy.carrier.NSizeGrid);
globalSCS = double(cfg.phy.numerology.scs_kHz);
[~, carriers] = sixgr.phy.frame.FrameRuntimeStateBuilder.build(cfg);
carrier = carriers{1};
active = carrier.configuredBWP(1, "DL");
activation = sixgr.phy.frame.AbsoluteTime.fromAbsoluteSlotSymbol( ...
    2, 0, active);
decision = carrier.BWPState.scheduleSwitch("DL", 0, activation, ...
    "ControlBWPID", 1, "TriggerSource", "RRC", ...
    "CommandID", "production-bwp-switch");
assert(decision.Accepted);
carrier.BWPState.applyUntil(activation);
assert(carrier.BWPState.ActiveDLBWPID == "0" && ...
    carrier.BWPState.ActiveULBWPID == "2");
assert(double(cfg.phy.carrier.NSizeGrid) == globalNRB && ...
    double(cfg.phy.numerology.scs_kHz) == globalSCS && ...
    globalNRB == nrb && globalSCS == scsKHz, ...
    "A BWP transition must not mutate the global carrier grid/numerology.");

multi = cfg;
cc0 = context.ComponentCarriers(1);
cc1 = cc0;
cc0.CarrierIndicatorMap = [ ...
    struct("Indicator", 0, "ScheduledCCID", 0); ...
    struct("Indicator", 1, "ScheduledCCID", 1)];
cc1.CCID = 1;
cc1.ServingCellID = 1;
cc1.SchedulingCCIDs = [0, 1];
cc1.CenterFrequencyHz = cc1.CenterFrequencyHz + 200e6;
cc1.DLCenterFrequencyHz = cc1.CenterFrequencyHz;
cc1.ULCenterFrequencyHz = cc1.CenterFrequencyHz;
cc1.CarrierIndicatorMap = struct("Indicator", 0, "ScheduledCCID", 1);
for index = 1:numel(cc1.BWPs)
    cc1.BWPs(index).CCID = 1;
    cc1.BWPs(index).ServingCellID = 1;
end
multi.phy.frame.componentCarriers = [cc0; cc1];
[multiSnapshot, multiCarriers] = ...
    sixgr.phy.frame.FrameRuntimeStateBuilder.build(multi);
assert(numel(multiSnapshot.ComponentCarriers) == 2 && ...
    numel(multiCarriers) == 2 && ...
    isequal([multiSnapshot.ComponentCarriers.CCID], [0, 1]), ...
    "Explicit multi-CC arrays must construct independent validated carriers.");
assert(multiSnapshot.ComponentCarriers(1).CarrierIndicatorMap(2). ...
    ScheduledCCID == 1);

bad = cfg;
badCarrier = context.ComponentCarriers(1);
badCarrier.DuplexMode = "FDD";
badCarrier.DLCenterFrequencyHz = badCarrier.CenterFrequencyHz;
badCarrier.ULCenterFrequencyHz = badCarrier.CenterFrequencyHz;
bad.phy.frame.componentCarriers = badCarrier;
localAssertError(@() sixgr.phy.frame.FrameRuntimeStateBuilder.build(bad), ...
    "sixgr:phy:frame:FDDRequiresSeparateFrequencies");

% Exercise an actual migrated FDD YAML through the full production config
% path.  The two directional centers must survive schema validation,
% internal-config construction, canonical frame resolution, and runtime
% CC serialization without being inferred from center_frequency_hz.
fddScenarioPath = fullfile(pwd, "configs", "lls", ...
    "lls_srs_strict_mini_anchor.yaml");
fddScenario = sixgr.lls6g.config.loadScenarioConfig( ...
    fddScenarioPath).toStruct();
assert(string(fddScenario.meta.scenario_id) == ...
    "lls_srs_strict_mini_anchor");
fddCfg = sixgr.lls6g.buildInternalConfig(fddScenario, runFolder);
dlCenterHz = double(fddScenario.frequency.dl_center_frequency_hz);
ulCenterHz = double(fddScenario.frequency.ul_center_frequency_hz);
assert(dlCenterHz ~= ulCenterHz);
assert(double(fddCfg.phy.duplex.fdd.dlCenterFrequencyHz) == dlCenterHz && ...
    double(fddCfg.phy.duplex.fdd.ulCenterFrequencyHz) == ulCenterHz);
assert(double(fddCfg.phy.frameStructure.FDDContexts.Downlink. ...
    CenterFrequencyHz) == dlCenterHz && ...
    double(fddCfg.phy.frameStructure.FDDContexts.Uplink. ...
    CenterFrequencyHz) == ulCenterHz);
fddCarrier = fddCfg.phy.frame.ComponentCarriers(1);
assert(string(fddCarrier.DuplexMode) == "FDD" && ...
    double(fddCarrier.DLCenterFrequencyHz) == dlCenterHz && ...
    double(fddCarrier.ULCenterFrequencyHz) == ulCenterHz, ...
    "The runtime carrier must preserve separate FDD directional centers.");

missingUL = fddScenario;
missingUL.frequency = rmfield(missingUL.frequency, ...
    "ul_center_frequency_hz");
localAssertError(@() sixgr.lls6g.buildInternalConfig( ...
    missingUL, runFolder), ...
    "sixgr:lls6g:config:MissingResolvedConfigValue");
equalCenters = fddScenario;
equalCenters.frequency.ul_center_frequency_hz = ...
    equalCenters.frequency.dl_center_frequency_hz;
localAssertError(@() sixgr.lls6g.buildInternalConfig( ...
    equalCenters, runFolder), ...
    "sixgr:phy:frame:FDDRequiresSeparateFrequencies");

fractionalTDRA = fddScenario;
fractionalTDRA.pdsch.start_symbol = 2.25;
localAssertRejected(@() sixgr.lls6g.buildInternalConfig( ...
    fractionalTDRA, runFolder), ...
    "A fractional PDSCH start_symbol must reach canonical TDRA " + ...
    "validation unchanged and be rejected, not rounded.");

ok = true;
end

function value = localBWP(id, startRB, sizeRB, active, controlID, ...
        dataID, scsKHz, cp)
value = struct( ...
    "bwp_id", id, ...
    "n_start_bwp", startRB, ...
    "n_size_bwp", sizeRB, ...
    "scs_khz", scsKHz, ...
    "cp_type", char(string(cp)), ...
    "active_initial", logical(active), ...
    "control_bwp_id", controlID, ...
    "data_bwp_id", dataID, ...
    "state_version", 0, ...
    "switch_activation_tick", 0);
end

function bwp = localSnapshotBWP(values, id, direction)
matches = [values.BWPID] == id & string({values.Direction}) == direction;
assert(nnz(matches) == 1, ...
    "Expected one %s BWP %d in the runtime snapshot.", direction, id);
bwp = values(matches);
end

function localAssertError(fcn, expectedIdentifier)
try
    fcn();
catch cause
    assert(string(cause.identifier) == string(expectedIdentifier), ...
        "Expected '%s'; received '%s': %s", ...
        expectedIdentifier, cause.identifier, cause.message);
    return;
end
error("sixgr:tests:ExpectedErrorNotRaised", ...
    "Expected error '%s' was not raised.", expectedIdentifier);
end

function localAssertRejected(fcn, failureMessage)
try
    fcn();
catch
    return;
end
error("sixgr:tests:ExpectedRejectionNotRaised", "%s", failureMessage);
end

function localCleanup(path)
if isfolder(path)
    rmdir(path, "s");
end
end
