function ok = testGeometryHybridAntennaDomain()
%TESTGEOMETRYHYBRIDANTENNADOMAIN Keep data and CSI-RS in one RF domain.

setup6GRSimToolkit("Verbose", false);

scenarioPath = fullfile("simulator", "configs", "scenarios", ...
    "master_geometry_based.yaml");
scenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
% The original master declares unqualified Type-II/subband CSI transport.
% Keep that rejection visible: this test does not qualify the master runner.
localReject(@() sixgr.lls6g.buildInternalConfig(scenario, ...
    fullfile(tempdir, "sixgr_geometry_hybrid_original_rejected")), ...
    "sixgr:mimo:UnqualifiedCSIWireLayout");
% Authored geometry/selected-basis fixture only. Use the supported four-port
% Type-I wideband report layout while retaining the master's antenna arrays,
% RF chains, 32 CSI-RS resources, and all operator/power assertions below.
fixture = scenario.toStruct();
fixture.mimo.codebook_type = 'type1';
fixture.canonical_control.mimo.codebook_type = 'type1';
fixture.csi_acquisition_and_reporting.report_configuration.frequency_granularity = 'wideband';
fixture.csi_acquisition_and_reporting.report_configuration.num_subbands = 1;
cfg = sixgr.lls6g.buildInternalConfig(fixture, ...
    fullfile(tempdir, "sixgr_geometry_hybrid_antenna_domain"));
assert(string(cfg.phy.csi.reportConfiguration.CodebookType)=="typeI-SinglePanel" && ...
    string(cfg.phy.csi.reportConfiguration.FrequencyGranularity)=="wideband" && ...
    cfg.phy.csi.reportConfiguration.NumSubbands==1, ...
    'Geometry fixture must execute its declared qualified report layout.');

arch = sixgr.rf.AntennaArrayFactory.resolvePortArchitecture(cfg, "bs", ...
    "Signal", "PDSCH", "MinimumPorts", 2);
assert(arch.HybridBeamformingEnabled, ...
    "Geometry truth must enable the configured hybrid element-domain path.");
assert(arch.NumElements == 64 && arch.NumPorts == 4 && ...
    arch.NumRFChains == 4 && arch.NumWaveformColumns == 64, ...
    "The master geometry scenario requires 64 elements, four logical ports and four RF chains.");
assert(isequal(size(arch.HybridElementToPortMatrix), [64 4]), ...
    "The resolved hybrid element-to-port matrix must be 64-by-4.");

csiPrecoders = double(cfg.phy.csirs.precoderMatrices);
assert(isequal(size(csiPrecoders), [64 4 32]), ...
    "CSI-RS must use the same 64-element domain with four ports and 32 resources.");
for resourceIndex = 1:size(csiPrecoders, 3)
    gram = csiPrecoders(:, :, resourceIndex)' * ...
        csiPrecoders(:, :, resourceIndex);
    assert(norm(gram - eye(4), "fro") <= 1e-10, ...
        "Every configured CSI-RS precoder must be semi-unitary.");
end

grant = struct( ...
    "Direction", "DL", "Frame", 0, "Slot", 0, "RNTI", 101, ...
    "UEIndex", 1, "ServingCell", 1, "PRBSet", 0:5, ...
    "SymbolAllocation", [2 10], "Modulation", "QPSK", ...
    "NumLayers", 2, "Layers", 2, "NumLogicalPorts", 2, ...
    "NumRFChains", 4, "TargetCodeRate", 0.3, "MCSIndex", 1);
% This is an authored configuration fixture, not received CSI. Selecting
% among 32 resources requires an explicit CRI; never invent one in runtime.
localReject(@() sixgr.phy.grant.freezePHYGrant(cfg, "DL", grant, ...
    "SNR_dB", 20, "Frame", 0, "Slot", 0), ...
    "sixgr:phy:grant:MissingDLCRIForCSIRSBasis");
grant.CRI = 0;
grant.PMI = 0;
localReject(@() sixgr.phy.grant.freezePHYGrant(cfg, "DL", grant, ...
    "SNR_dB", 20, "Frame", 0, "Slot", 0), ...
    "sixgr:phy:grant:CSIRSPortBasisShapeMismatch");
% Four CSI ports define the selected PMI basis; two data layers do not
% reduce that basis to two logical ports.
grant.NumLogicalPorts = size(csiPrecoders, 2);
phyGrant = sixgr.phy.grant.freezePHYGrant(cfg, "DL", grant, ...
    "SNR_dB", 20, "Frame", 0, "Slot", 0);
physicalMatrix = double(phyGrant.PrecodingState.Matrix);
assert(isequal(size(physicalMatrix), [64 2]) && ...
    phyGrant.AntennaArchitecture.NumWaveformColumns == 64, ...
    "Frozen DL authority must retain the 64-element waveform domain.");
assert(abs(sum(abs(physicalMatrix(:)).^2) - 1) <= 1e-12, ...
    "The frozen physical PDSCH precoder must use unit-total-power normalization.");
assert(phyGrant.PrecodingState.CSIRSPortBasisApplied && ...
    phyGrant.PrecodingState.CSIResourceIndex == grant.CRI && ...
    isequal(size(phyGrant.PrecodingState.MatrixLogicalPorts), [4 2]), ...
    "Frozen rank two must preserve its explicitly selected four-port CSI basis.");
expected = csiPrecoders(:,:,grant.CRI+1) * ...
    double(phyGrant.PrecodingState.MatrixLogicalPorts);
assert(norm(physicalMatrix-expected, "fro") <= 1e-12, ...
    "The physical matrix must be the selected CSI beam basis times PMI.");

ok = true;
end

function localReject(operation, identifier)
try
    operation();
catch exception
    assert(string(exception.identifier) == identifier, ...
        "Unexpected rejection: %s | %s", exception.identifier, exception.message);
    return;
end
error("testGeometryHybridAntennaDomain:MissingRejection", ...
    "Expected rejection %s.", identifier);
end
