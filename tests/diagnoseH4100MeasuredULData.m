function folder=diagnoseH4100MeasuredULData(grantFolder)
% One actual coded data reception for a retained measured-SRS/received-DCI
% grant. This independent CDL/RF episode does NOT continue the earlier SRS
% or control channel history. A CRC failure is retained, not tuned away.
setup6GRSimToolkit('Verbose',false);
inputs=fullfile(string(grantFolder),["scheduled_grant.mat", ...
    "received_grant_transmitter.mat","measured_ul_grant.csv","sources.mat"]);
assert(all(isfile(inputs)),'test:MissingMeasuredULGrant');
inputHashes=arrayfun(@(p)string(sixgr.util.sha256File(p)),inputs);
scheduled=load(inputs(1),'dataCfg','grant','frozen','scope');
transmitted=load(inputs(2),'tx','txInfo','payload','assignment');
priorSources=load(inputs(4));
for n=1:numel(priorSources.files)
    assert(priorSources.hashes(n)==string(sixgr.util.sha256File(priorSources.files(n))), ...
        'test:ChangedMeasuredGrantSource');
end
policyFile='simulator/configs/validation/h4_100_installed_pdcch_development.yaml';
p=sixgr.lls6g.config.readConfigFile(policyFile);
episode=p.cases(string({p.cases.id})=="present_uplink_grant");
folder=fullfile(pwd,'results','diagnostics','h4_measured_ul_data', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
assert(~isfolder(folder)); mkdir(folder);
files=[string(mfilename('fullpath'))+".m";string(policyFile); ...
    string(which('sixgr.phy.ul.PUSCH_Rx')); ...
    string(which('sixgr.rf.runtime.RFImpairmentStream')); ...
    string(which('sixgr.channel.ChannelFactory')); ...
    string(which('sixgr.phy.rx.compensateReceivedAGC'))];
hashes=arrayfun(@(f)string(sixgr.util.sha256File(f)),files);
scope="measured_SRS_received_DCI_then_independent_reset_PUSCH_not_continuous_runtime";
save(fullfile(folder,'sources.mat'),'inputs','inputHashes','files','hashes','scope');
cfg=scheduled.dataCfg; frozen=scheduled.frozen; grant=scheduled.grant;
cfg.run.rootRunFolder=folder;
cfg.phy.runtimeSignalFamily="PUSCH"; cfg.lls6g.userContext.RuntimeSignalFamily="PUSCH";
user=cfg.lls6g.userContext; tx=transmitted.tx; txInfo=transmitted.txInfo;
fs=double(txInfo.OFDM.SampleRate); epoch=cfg.rf.configurationEpoch;
nTx=user.RuntimeUEAntennaMeta.NumElements; nRx=user.RuntimeServingBSAntennaMeta.NumElements;
assert(fs==122.88e6 && nTx==4 && nRx==64 && tx.PUSCH.NumLayers==grant.NumLayers && ...
    size(tx.Waveform,2)==nTx && tx.TransportBlockSize==frozen.CodingLayout.TBSBits);
margin=double(p.guard_samples);
[powered,power]=sixgr.rf.applyPowerContext(tx.Waveform,cfg,"UL",txInfo,'ApplyPA',false);
cfg.lls6g.runtimePowerContext=power;
assert(~power.PAApplied && (~power.PAEnabled || power.PAExecutionDeferred));
samples=[powered;zeros(margin,nTx,'like',powered)];
identity=struct('RunId',"measured_SRS_received_DCI_UL_data",'TrialId',"independent_PUSCH_episode");
fprintf('H4_MEASURED_UL_DATA_START rank=%g MCS=%g PRBs=%g folder=%s\n', ...
    grant.NumLayers,grant.MCSIndex,numel(grant.PRBSet),folder);
txRF=sixgr.rf.runtime.RFImpairmentStream(cfg,'tx','UL',fs,nTx,0,epoch,false,identity);
emitted=txRF.apply(sixgr.phy.waveform.WaveformChunk(samples,0),epoch);
channel=sixgr.channel.ChannelFactory.createRuntimeChannelState(cfg,'UL', ...
    'UEIndex',p.ue_index,'ServingCell',p.serving_cell,'Seed',episode.channel_seed, ...
    'AbsoluteSampleIndex',0);
channel=sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    channel,cfg,emitted.Waveform,txInfo,'NumTxAnt',nTx,'NumRxAnt',nRx, ...
    'TransmitAntennaRuntime',user.RuntimeUEAntenna,'ReceiveAntennaRuntime',user.RuntimeServingBSAntenna, ...
    'TransmitAntennaMeta',user.RuntimeUEAntennaMeta,'ReceiveAntennaMeta',user.RuntimeServingBSAntennaMeta);
assert(channel.CurrentSampleIndex==0 && channel.TotalIdleAdvancedSamples==0);
[propagated,replay]=sixgr.channel.ChannelFactory.applyRuntimeChannelState( ...
    channel,emitted.Waveform,'OutputSampleAlignment','continuous_raw_samples');
[antenna,noise]=sixgr.phy.waveform.addOccupiedREAWGN(propagated,tx.Carrier, ...
    cfg.channel.snr_dB,'Seed',episode.noise_seed, ...
    'SignalEnergyPerOccupiedRE',sixgr.link.resolveAWGNReferenceEnergy(cfg));
rxRF=sixgr.rf.runtime.RFImpairmentStream(cfg,'rx','UL',fs,nRx,0,epoch,false,identity);
frontend=rxRF.apply(sixgr.phy.waveform.WaveformChunk(antenna,0),epoch);
rawWaveform=frontend.Waveform;
raw=sixgr.phy.waveform.WaveformObservationBuffer(0,size(rawWaveform,1),fs,nRx);
raw.append(frontend.Chunk,fs);
segment=struct('StartSample',0,'EndSampleExclusive',size(rawWaveform,1), ...
    'Execution',struct('RX',struct('ID','gnb','Replay',frontend.Replay)));
[received,gain]=sixgr.phy.rx.compensateReceivedAGC(raw,{segment},'gnb');
waveform=received.readComplete(); rfReplay=struct('TX',emitted.Replay,'RX',frontend.Replay);
rfRows=[struct2table(emitted.Row);struct2table(frontend.Row)];
sixgr.util.csvWriteTable(fullfile(folder,'rf_chain_measurements.csv'),rfRows,'PreserveSchema',true);
save(fullfile(folder,'receiver_input.mat'),'cfg','frozen','waveform', ...
    'rawWaveform','gain','rfReplay','noise','replay','power','margin','scope','-v7.3');
% The gNB's pre-transmission frozen grant owns receive layout. No UE TX
% object, payload, received assignment, injected timing/noise/CFO or channel
% truth enters the decoder.
[rx,info]=sixgr.phy.ul.PUSCH_Rx(waveform,cfg,'PHYGrant',frozen, ...
    'TimingSearchWindowSamples',[0 margin]);
save(fullfile(folder,'receiver_output.mat'),'rx','info','scope','-v7.3');
crc=all(rx.CRCPass); exact=crc && isequal(rx.TransportBlock,transmitted.payload);
assert(~crc || exact,'test:MeasuredULWrongDecodedPayload');
row=table(grant.NumLayers,grant.MCSIndex,string(grant.Modulation),grant.TargetCodeRate, ...
    numel(grant.PRBSet),tx.TransportBlockSize,crc,exact,rx.TimingOffset, ...
    rx.AppliedTimingCorrection_samples,rx.EstimatedCFO_Hz, ...
    string(mat2str(rx.PostEqSINRPerLayer_dB)),string(rx.PostEqSINRValueStatus), ...
    false,false,scope,'VariableNames',{'Rank','MCS','Modulation','CodeRate','NumPRB', ...
    'TBSBits','CRCPass','ExactPayloadRecovered','TimingEstimateSamples','AppliedTimingSamples', ...
    'EstimatedCFO_Hz','LayerSINR_dB','SINRStatus','ScenarioAccepted','StatisticallyQualified','Scope'});
sixgr.util.csvWriteTable(fullfile(folder,'received_ul.csv'),row,'PreserveSchema',true, ...
    'RoundTripNumericText',true);
assert(isequal(hashes,arrayfun(@(f)string(sixgr.util.sha256File(f)),files)) && ...
    isequal(inputHashes,arrayfun(@(f)string(sixgr.util.sha256File(f)),inputs)), ...
    'test:MeasuredULDataSourcesChanged');
receipt=struct('Completed',true,'CRCPass',crc,'ExactPayloadRecovered',exact, ...
    'ScenarioAccepted',false,'StatisticallyQualified',false,'Scope',scope, ...
    'SourceFiles',files,'SourceSHA256',hashes,'InputFiles',inputs,'InputSHA256',inputHashes);
sixgr.util.jsonWrite(fullfile(folder,'receipt.json'),receipt);
disp(row);
fprintf('H4_MEASURED_UL_DATA_COMPLETE CRC=%d exact_payload=%d scenario_accepted=0\n',crc,exact);
end
