function ok=testH4100SharedSRSScoring()
% One actual H4 UL SRS occasion through the shared CDL-C/RF sample clock.
% Declared preconnected clock/TAG inputs are not evidence of acquired access.
setup6GRSimToolkit('Verbose',false);
source=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_short.yaml');
prior=rng; cleanup=onCleanup(@()rng(prior)); %#ok<NASGU>
rng(double(source.get('simulation.random_seed')),'twister');
folder=fullfile(pwd,'results','lls','h4_shared_srs_scoring', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(folder);
cfg=sixgr.lls6g.buildInternalConfig(source,folder); cfg.run.rootRunFolder=folder;
multi=struct('Enabled',true,'NumUsers',1,'RNTIStart',1, ...
    'ExecutionModel','slot_coupled_truth');
state=sixgr.truth.CoupledTruthRuntime.initialize(cfg,folder,multi,struct(),40);
state=sixgr.truth.CoupledTruthRuntime.advanceFrame(state,cfg,multi,1,40);
state=sixgr.truth.CoupledTruthRuntime.startSlot(state,cfg,'DL',1,1,1,cfg.run.totalSlots,40);
state.CurrentServingIdx(:)=1;
[state,owner]=sixgr.truth.CoupledWaveformStream.initialize(state,cfg,{cfg});
firstSlot=double(cfg.phy.srs.period_offset)+1;
plan=sixgr.truth.CoupledTruthRuntime.futureULPlanningView(state,firstSlot);
[ul,~]=sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg,plan,1,'UL');
ul=sixgr.phy.grid.applyRuntimeCarrierTimeline(ul,firstSlot);
% Typed protocol-boundary fixtures, exactly as used by the shared CSI/UCI
% component. No PBCH/PRACH/RRC success is exported or inferred here.
carrier=sixgr.phy.grid.makeCarrier(ul); fs=owner.SampleRateHz;
reference=struct('Source',"received_SSB_timing_and_decoded_BCH", ...
    'NCellID',carrier.NCellID,'SampleRateHz',fs, ...
    'DLPhaseOffsetSamples',0,'AvailableAtSample',0);
common=struct('Source',"decoded_sib1", ...
    'TimingAdvanceOffsetPresent',false,'TimingAdvanceOffset',"");
ul.SharedULTimingContext=struct('DLReference',reference, ...
    'Offset',sixgr.phy.frame.resolveULTimingAdvanceOffset(common,'FR1'), ...
    'ReceivedRARTiming',sixgr.phy.ra.resolveRARTimingAdvance(0,30,fs), ...
    'TimingAdvanceAvailableAtSample',0,'TimingAdvanceEffectiveAtSample',0, ...
    'TimeAlignmentExpirySampleExclusive',round(.03*fs));
args={'SlotIndex',firstSlot,'TrialIndex',1,'SNR_dB',40,'TimingAdvanceSamples',0};
pending=sixgr.link.runSRSChannelEstimation(ul,args{:},'PrepareOnly',true);
p=pending.PreparedTransmission;
save(fullfile(folder,'prepared.mat'),'p','pending','cfg','ul','-v7.3');
fprintf('H4_SRS_PREPARED tx=%d rx=%d prb=%d scs=%g fs=%g ports=%d occupied_prb=%g CSRS=%g\n', ...
    p.NumPhysicalTransmitAntennas,p.NumReceiveAntennas,p.Tx.Carrier.NSizeGrid, ...
    p.Tx.Carrier.SubcarrierSpacing,p.SampleRateHz,p.Tx.SRS.NumSRSPorts, ...
    pending.SRSOccupiedPRBCount,p.Tx.SRS.CSRS);
assert(p.NumPhysicalTransmitAntennas==4 && p.NumReceiveAntennas==64 && ...
    p.Tx.Carrier.NSizeGrid==273 && p.Tx.Carrier.SubcarrierSpacing==30 && ...
    p.SampleRateHz==122.88e6 && p.Tx.SRS.NumSRSPorts==4 && ...
    pending.SRSOccupiedPRBCount==272, ...
    'Exercise the actual H4 wideband sounding allocation, not direct-TX defaults.');
owner.queueUplinkControl(1,p,struct('Config',ul,'Arguments',{args},'ServingCell',1));
scope=struct('Scope',"one_shared_H4_SRS_occasion_declared_access_TAG_boundary", ...
    'AccessExecuted',false,'ScenarioAccepted',false,'StatisticallyQualified',false, ...
    'SourceScenario',string(source.ConfigPath));
save(fullfile(folder,'configuration.mat'),'cfg','scope');
fprintf('H4_SHARED_SRS_SCORING_ROOT=%s\n',folder);
seen=false;
for slot=1:firstSlot+1
    state.CurrentSlot=slot;
    current=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,slot);
    [state,items]=owner.advanceSlot(state,current);
    fprintf('H4_SHARED_SRS_SCORING_SLOT=%d/%d\n',slot,firstSlot+1);
    for item=items
        assert(item.Kind=="SRS" && ~seen,'Only the queued SRS receiver may complete.');
        seen=true; c=item.Context; p=c.Prepared;
        [~,pre,tx,replay,received]=sixgr.truth.sharedObservationEvidence(item.Planes,p);
        [desired,referenceEvidence]=sixgr.truth.sharedLinkScoringObservation( ...
            item.Planes,p,c.DesiredReferencePlane);
        input=struct('Prepared',p,'Observation',received,'PhysicalMeasurementObservation',pre, ...
            'TransmitterObservation',tx,'Replay',replay,'DesiredReferenceObservation',desired, ...
            'DesiredReferenceEvidence',referenceEvidence, ...
            'ChannelState',owner.directionalChannelState(1,'UL'));
        receivedWaveform=received.readComplete(); referenceWaveform=desired.readComplete();
        save(fullfile(folder,'received.mat'),'p','ul','args','replay','receivedWaveform', ...
            'referenceWaveform','referenceEvidence','scope','input','-v7.3');
        before=owner.Events.NextSampleIndex;
        [state,out,capture]=sixgr.truth.receiveSharedSRSMeasurement(state,item,input);
        assert(isnan(out.PilotCommonPhaseRate_Hz) && out.PilotPhasePairCount==0 && ...
            isnan(out.EstimatedDopplerHz) && isnan(out.InjectedDoppler_Hz) && ...
            ~isempty(state.SRSPilotPhaseHistoryByUE{1}));
        % Preserve completed physical receiver evidence before testing its
        % CSV schema. Publication failures must not lose the receiver result.
        save(fullfile(folder,'result.mat'),'out','capture','scope','-v7.3');
        row=table(slot,out.Ok,out.NMSE_dB,out.TrueChannelNMSE_dB,out.RawChannelNMSE_dB, ...
            out.SRSOccupiedPRBCount,out.NoiseVariance,out.RIEstimate,out.TPMIEstimate, ...
            string(out.NoiseVarSource),string(out.NMSEReferenceSource),false,false, ...
            'VariableNames',{'CompletionSlot','StrictOk','NMSE_dB','TrueChannelNMSE_dB','RawNMSE_dB', ...
            'OccupiedPRBCount','NoiseVariance','RI','TPMI','NoiseSource', ...
            'NMSEReferenceSource','ScenarioAccepted','StatisticallyQualified'});
        row=sixgr.truth.bindSharedSRSNMSEEvidence(row,out);
        phase=sixgr.link.srsPilotPhaseEvidence(out);
        for field=string(fieldnames(phase)).', row.(field)=phase.(field); end
        assert(row.ChannelNMSEErrorEnergy==out.ChannelNMSEScoring.ErrorEnergy && ...
            row.ChannelNMSEReferenceEnergy==out.ChannelNMSEScoring.ReferenceEnergy && ...
            row.RawChannelNMSEErrorEnergy==out.RawChannelNMSEScoring.ErrorEnergy && ...
            row.RawChannelNMSEReferenceEnergy==out.RawChannelNMSEScoring.ReferenceEnergy);
        sixgr.util.csvWriteTable(fullfile(folder,'srs_result.csv'),row,'PreserveSchema',true);
        disp(row(:,1:11));
        assert(before==owner.Events.NextSampleIndex, ...
            'Scoring must not execute another channel/RF interval.');
        assert(size(capture.Rx.Hest,3)==64 && size(capture.Rx.Hest,4)==4 && ...
            out.ChannelNMSEScoring.Available && ...
            isequal(out.ChannelNMSEReferenceEvidence.ScoringEstimatorInfo.CDMLengths,[4 1]) && ...
            out.ChannelNMSEReferenceEvidence.ReceiverTimingIncluded && ...
            out.ChannelNMSEReferenceEvidence.ReceiverCFOIncluded && ...
            ~out.ChannelNMSEReferenceEvidence.ReceiverEstimatorInput && ...
            ~capture.RxInfo.ChannelEstimation.PrimaryEstimatorFallbackUsed);
        assert(out.Ok,'sixgr:test:H4SharedSRSQualificationFailed', ...
            'Exact impaired H4 SRS failed: %s; NMSE=%g dB. Evidence: %s', ...
            out.FailureReason,out.NMSE_dB,folder);
    end
end
assert(seen && ~owner.hasPending('SRS',1));
fprintf('H4_SHARED_SRS_SCORING_PASS evidence=%s\n',folder);
ok=true;
end
