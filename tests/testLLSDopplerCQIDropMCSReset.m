function ok = testLLSDopplerCQIDropMCSReset()
%TESTLLSDOPPLERCQIDROPMCSRESET Guard CQI-domain AMC against stale high-MCS grants.

setup6GRSimToolkit("Verbose", false);

cfg = sixgr.config.defaultConfig();
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.mode", "amc");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.domain", "cqi");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.dlPolicy", "baseline");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.rankPolicy", "fixed");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.beamPolicy", "fixed");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.innerLoopFlag", true);
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.outerLoopFlag", true);
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.deltaMCSPolicy", "olla");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.cqiSmoothingMode", "doppler_adaptive");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.cqiSmoothingAlpha", 0.35);
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.mcsJumpResetThreshold", 5);
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.ollaStepUp", 0.1);
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.ollaStepDown", 0.9);
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.deltaMCSMin", -6);
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.deltaMCSMax", 6);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.mcsTable", "qam256_table2");
cfg = sixgr.util.structSet(cfg, "phy.csi.cqiTable", "table1");
cfg = sixgr.util.structSet(cfg, "phy.numerology.slotDuration_ms", 0.5);
cfg = sixgr.util.structSet(cfg, "channel.doppler_Hz", 370.37037037);

amcFromCQI7 = sixgr.link.resolveMCSFromCQI(7, "qam256_table2", "table1");
assert(logical(amcFromCQI7.Valid) && double(amcFromCQI7.MCSIndex) == 5, ...
    "The focused regression must use the same CQI7 -> MCS5 mapping observed in the DL failure.");

previousState = struct( ...
    "Initialized", true, ...
    "SmoothedCQI", 12, ...
    "CQIBasedMCS", 13, ...
    "LastMCSIndex", 13, ...
    "LastInstantaneousMCS", 15, ...
    "DeltaMCS", 0.1, ...
    "UpdateCount", 12);
metrics = struct( ...
    "CQI", 7, ...
    "RI", 1, ...
    "PMI", 3, ...
    "SINR_dB", 11.9891819630906, ...
    "CSIAgeSlots", 4, ...
    "CombinedDecodeOK", false);

[decision, nextState] = sixgr.link.computeLinkAdaptationDecision(cfg, "DL", metrics, ...
    "AdaptationState", previousState);

assert(logical(decision.StateReset) && string(decision.StateResetReason) == "mcs_jump", ...
    "A measured CQI-derived MCS collapse must reset stale high-MCS state.");
assert(double(decision.CQIBasedMCS) == double(amcFromCQI7.MCSIndex), ...
    "After MCS-jump reset, CQIBasedMCS must come from the current measured CQI.");
assert(double(decision.MCSIndex) <= double(amcFromCQI7.MCSIndex), ...
    "The next DL grant MCS must not stay above the current CQI-derived MCS after reset.");
assert(double(nextState.DeltaMCS) <= 0, ...
    "The reset must clear stale positive OLLA before selecting the next DL grant.");
assert(double(decision.EffectiveCQISmoothingAlpha) >= double(decision.CQISmoothingAlpha), ...
    "Doppler aging must not reduce responsiveness to the newest measured CQI.");

ok = true;
end
