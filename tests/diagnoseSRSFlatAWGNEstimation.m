function result=diagnoseSRSFlatAWGNEstimation(capturePath,outputFolder)
% Read-only retained-IQ comparison of the production opt-in AWGN receiver.
% Candidate input: received grid and configured SRS sequence only. Applied
% channel references are used exclusively after estimation for scoring.
setup6GRSimToolkit('Verbose',false);
retained=load(capturePath,'capture'); c=retained.capture;
prepared=c.Prepared;
assert(prepared.Channel=="SRS",'test:SRSOnly','Require an actual SRS capture.');
wave=c.RXAfterDigitalGainCompensation;
window=[0,size(wave,1)-size(prepared.Tx.Waveform,1)];
[rx,info]=sixgr.phy.ul.SRS_Rx(wave,prepared.ReceiverConfig, ...
    'Carrier',prepared.Tx.Carrier,'SRS',prepared.Tx.SRS, ...
    'TimingSearchWindowSamples',window,'StrictNoiseVarianceRequired',true);
assert(~sixgr.util.structGet(info,'ChannelEstimation.PrimaryEstimatorFallbackUsed',false), ...
    'test:SRSUnexpectedEstimatorFallback','Diagnose the primary estimator explicitly.');
carrier=rx.Carrier; srs=rx.SRS;
reference=nrResourceGrid(carrier,srs.NumSRSPorts);
indices=nrSRSIndices(carrier,srs); reference(indices)=nrSRS(carrier,srs);
K=size(rx.RxGrid,1); L=size(rx.RxGrid,2); R=size(rx.RxGrid,3);
P=double(srs.NumSRSPorts);
X=reshape(reference,K*L,P); Y=reshape(rx.RxGrid,K*L,R);
occupied=any(X~=0,2); X=X(occupied,:); Y=Y(occupied,:);
assert(size(X,1)>P && rank(X)==P,'test:SRSUnidentifiableFlatFit', ...
    'A constant multiport fit needs independent configured reference columns.');
% Test the receiver component against an independent direct LS solve.
% This replay does not select/install the candidate in scenario runtime.
fit=sixgr.phy.rx.estimateFlatAWGNMultiportChannel(Y,X);
gain=fit.GainPerPortReceiveBranch;
assert(norm(gain-X\Y,'fro')<1e-10,'test:SRSFlatFitMismatch', ...
    'The component must agree with the independent multiport LS solve.');
noisePerBranch=fit.NoiseVariancePerReceiveBranch;
candidateCfg=prepared.ReceiverConfig;
candidateCfg.phy.srs.runtimeChannelEstimator='flat_static_awgn_ls';
receiverReplay=c.ExecutionReplay;
receiverReplay.ReceiverID=c.DesiredLinkScoringEvidence.ReceiverID;
receiverReplay.TransmitterID=c.DesiredLinkScoringEvidence.TransmitterID;
[candidateRx,candidateInfo]=sixgr.phy.ul.SRS_Rx(wave,candidateCfg, ...
    'Carrier',prepared.Tx.Carrier,'SRS',prepared.Tx.SRS, ...
    'TimingSearchWindowSamples',window,'StrictNoiseVarianceRequired',true, ...
    'ReceivedExecutionEvidence',receiverReplay);
candidate=candidateRx.Hest;
independent=repmat(reshape(gain.',1,1,R,P),K,L,1,1);
assert(max(abs(candidate(:)-independent(:)))<1e-12 && ...
    abs(candidateRx.NoiseVar-fit.NoiseVariance)<1e-12, ...
    'test:SRSProductionFitMismatch','Production receiver differs from independent pilot LS.');
[actualReference,referenceEvidence]=sixgr.truth.sharedSRSReferenceGrid( ...
    prepared,c.AppliedChannelReferenceSegments,c.ExecutionReplay,rx.Timing,info.OFDMInfo);
original=sixgr.phy.srs.pilotChannelNMSE(rx.Hest,actualReference,indices);
proposed=sixgr.phy.srs.pilotChannelNMSE(candidate,actualReference,indices);
result=struct('CapturePath',string(capturePath), ...
    'Scope',"production_receiver_retained_IQ_replay_not_full_scenario_acceptance", ...
    'EstimatorInput',"received_grid_and_configured_SRS_reference_only", ...
    'ScoringReferenceUsedByEstimator',false, ...
    'TransmittedPayloadUsedByEstimator',false, ...
    'PilotRECount',size(X,1),'NumSRSPorts',P,'NumReceiveAntennas',R, ...
    'ReferenceConditionNumber',cond(X), ...
    'MeasuredTimingOffset_samples',rx.Timing.AppliedTimingCorrectionSamples, ...
    'OriginalNMSE_dB',original.dB,'CandidateNMSE_dB',proposed.dB, ...
    'OriginalNoiseVariance',rx.NoiseVar, ...
    'CandidateNoiseVariance',candidateRx.NoiseVar, ...
    'CandidateNoiseSource',string(candidateRx.NoiseVarSource), ...
    'InjectedGridNoiseVarianceScoringOnly',c.ExecutionReplay.ReferenceAWGNGridNoiseVariance);
if ~isfolder(outputFolder), mkdir(outputFolder); end
[~,tag]=fileparts(capturePath);
writetable(struct2table(result),fullfile(outputFolder,tag+"_flat_candidate.csv"));
save(fullfile(outputFolder,tag+"_flat_candidate.mat"),'result','gain','noisePerBranch', ...
    'original','proposed','referenceEvidence','info','candidateInfo');
disp(result);
end
