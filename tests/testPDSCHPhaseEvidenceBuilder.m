function ok = testPDSCHPhaseEvidenceBuilder()
%TESTPDSCHPHASEEVIDENCEBUILDER Validate production-derived phase tables.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
root = fullfile(fileparts(mfilename("fullpath")), "vectors", "pdsch");
tables = sixgr.pdsch.PDSCHPhaseEvidenceBuilder.build(root);

requiredFields = [ ...
    "pdsch_assignment_resolution", ...
    "pdsch_resource_ownership", ...
    "pdsch_re_mapping", ...
    "pdsch_dmrs_matrix", ...
    "pdsch_ptrs_matrix", ...
    "pdsch_coding_chain", ...
    "pdsch_independent_vector_results", ...
    "pdsch_layer_codeword_map", ...
    "pdsch_precoding_application", ...
    "pdsch_harq_trials", ...
    "pdsch_negative_tests"];
assert(isequal(sort(string(fieldnames(tables))), sort(requiredFields(:))), ...
    "Evidence builder returned an unexpected table set.");

contract = localReadStrings(fullfile(root, ...
    "desired_pdsch_csv_contract.csv"));
for i = 1:numel(requiredFields)
    field = requiredFields(i);
    fileName = field + ".csv";
    contractRow = contract(contract.FileName == fileName, :);
    assert(height(contractRow) == 1, ...
        "Missing contract row for %s.", fileName);
    expectedColumns = split(contractRow.RequiredColumns, "|").';
    if any(fileName == [ ...
            "pdsch_dmrs_matrix.csv", "pdsch_ptrs_matrix.csv"])
        expectedColumns = [expectedColumns, "PlotCoordinates0Based"];
    end
    actual = tables.(field);
    assert(istable(actual) && height(actual) > 0, ...
        "%s must be a nonempty table.", field);
    assert(isequal(string(actual.Properties.VariableNames), ...
        expectedColumns), "%s schema differs from exact contract.", field);
    assert(all(upper(string(actual.Status)) == "PASS"), ...
        "%s contains a non-passing evidence row.", field);
    keys = split(contractRow.PrimaryKey, "|").';
    combined = strings(height(actual), numel(keys));
    for k = 1:numel(keys)
        combined(:, k) = string(actual.(keys(k)));
        assert(all(strlength(strtrim(combined(:, k))) > 0), ...
            "%s has an empty primary-key value in %s.", ...
            field, keys(k));
    end
    assert(numel(unique(join(combined, char(31), 2))) == height(actual), ...
        "%s contains duplicate primary keys.", field);
end

assignment = tables.pdsch_assignment_resolution;
assert(height(assignment) == 22, ...
    "All 22 frozen assignment cases must execute.");
created = localTruth(assignment.AssignmentCreated);
allowed = localTruth(assignment.WaveformAllowed);
assert(all(~allowed | created), ...
    "No rejected assignment may allow waveform generation.");
assert(all(strlength(assignment.ErrorIdentifier(~created)) > 0), ...
    "Every rejected assignment must carry its observed typed error.");
assert(all(assignment.Source(created) == ...
    ["decoded_dci+ue_context";"calibration_assignment"; ...
     "calibration_assignment";"decoded_dci+ue_context"; ...
     "decoded_dci+ue_context";"sps_activation_dci+rrc_context"]), ...
    "Passing assignment rows do not carry observed factory sources.");

ownership = tables.pdsch_resource_ownership;
assert(height(ownership) == 2016 ...
    && all(str2double(ownership.CollisionCount) == 0), ...
    "All positive reserved-RE vectors must emit collision-free ownership.");
mapping = tables.pdsch_re_mapping;
assert(isequal(sort(unique(upper(mapping.Domain))), ...
    ["DATA";"DMRS";"PTRS";"RESERVED"]), ...
    "The explicit resource plan must emit all four RE domains.");
assert(height(mapping) == 168 ...
    && numel(unique(str2double(mapping.LinearIndex0Based))) == 168, ...
    "The diagnostic resource plan must account for every RE exactly once.");

dmrs = tables.pdsch_dmrs_matrix;
assert(height(dmrs) == 133 ...
    && all(str2double(dmrs.IndexMismatchCount) == 0) ...
    && all(str2double(dmrs.SequenceNMSE) <= 1e-12) ...
    && all(strlength(dmrs.SequenceDigest) == 64), ...
    "All 133 valid DM-RS vectors must have exact indices and sequences.");
ptrs = tables.pdsch_ptrs_matrix;
assert(height(ptrs) == 53, ...
    "All 53 nonnegative PT-RS presence vectors must execute.");
present = localTruth(ptrs.ExpectedPresent);
assert(nnz(present) == 48 && nnz(~present) == 5 ...
    && all(str2double(ptrs.PTRSRECount(present)) > 0), ...
    "PT-RS present/absent coverage or RE counts changed.");
cpeBefore = str2double(ptrs.CPEBeforeDeg);
cpeAfter = str2double(ptrs.CPEAfterDeg);
evmBefore = str2double(ptrs.EVMBeforePercent);
evmAfter = str2double(ptrs.EVMAfterPercent);
assert(all(cpeBefore > 1e-6) && all(evmBefore > 1e-6), ...
    ["Every PT-RS evidence row must contain an actual nonzero " ...
    "phase-noise impairment of emitted production data REs."]);
assert(all(cpeAfter(present) < cpeBefore(present) - 1e-8) ...
        && all(evmAfter(present) < evmBefore(present) - 1e-8), ...
    "Production PT-RS correction must improve every present case.");
assert(all(abs(cpeAfter(~present) - cpeBefore(~present)) <= 1e-10) ...
        && all(abs(evmAfter(~present) - evmBefore(~present)) <= 1e-10), ...
    "PT-RS-absent production cases must not claim phase correction.");

coding = tables.pdsch_coding_chain;
canonicalCoding = startsWith(coding.CaseID, "TBS-");
reservationCoding = startsWith(coding.CaseID, "RES-");
assert(height(coding) == 15 ...
    && nnz(canonicalCoding) == 4 ...
    && nnz(reservationCoding) == 11 ...
    && all(localTruth(coding.CRCOK)) ...
    && isequal(sort(unique(str2double(coding.BaseGraph))), [1;2]) ...
    && all(str2double(coding.G) == str2double(coding.RateMatchedBits)), ...
    ["Explicit coding evidence must contain four canonical BG1/BG2 " ...
    "round trips plus 11 aligned reservation executions."]);
reservationRows = coding(reservationCoding, :);
ownershipCases = string(ownership.CaseID);
owner = lower(string(ownership.Owner));
for i = 1:height(reservationRows)
    mask = ownershipCases == reservationRows.CaseID(i);
    assert(any(mask), ...
        "Reservation coding row %s has no aligned ownership execution.", ...
        reservationRows.CaseID(i));
    expectedG = 2 * nnz(mask & owner == "pdsch_data");
    assert(str2double(reservationRows.G(i)) == expectedG ...
        && str2double(reservationRows.TBS(i)) == 64 ...
        && localTruth(reservationRows.CRCOK(i)), ...
        ["Reservation coding row %s is not the exact QPSK G/TBS/CRC " ...
        "execution of its aligned ownership map."], ...
        reservationRows.CaseID(i));
end
baselineG = str2double(reservationRows.G( ...
    reservationRows.CaseID == "RES-001"));
sameGeometry = false(height(reservationRows), 1);
reservedCount = zeros(height(reservationRows), 1);
for i = 1:height(reservationRows)
    mask = ownershipCases == reservationRows.CaseID(i);
    sameGeometry(i) = nnz(mask) == 168;
    reservedCount(i) = nnz(mask & startsWith(owner, "reserved"));
end
assert(isscalar(baselineG) && ...
    all(str2double(reservationRows.G( ...
        sameGeometry & reservedCount > 0)) < baselineG), ...
    ["Every aligned 168-RE reserved execution must reduce exact G " ...
    "relative to the real unreserved RES-001 execution."]);

independent = tables.pdsch_independent_vector_results;
mandatory = [ ...
    "scrambling","modulation","layer_mapping","tbs","tb_crc", ...
    "ldpc_segmentation","ldpc_encoding","rate_matching", ...
    "dmrs_positions","dmrs_ports","dmrs_sequence","ptrs_indices", ...
    "reserved_re","precoding_application","harq_combining", ...
    "receiver_chain"];
assert(isempty(setdiff(mandatory, lower(independent.VectorFamily))), ...
    "A mandatory independent family is absent.");
assert(all(str2double(independent.MismatchCount) == 0) ...
    && all(str2double(independent.MaxAbsError) ...
        <= str2double(independent.Tolerance) + 1e-15) ...
    && all(independent.ExpectedDigest == independent.ActualDigest), ...
    "Independent evidence contains a mismatch.");
hashExpression = "^[0-9a-f]{64}$";
assert(all(~cellfun("isempty", regexp( ...
    cellstr(independent.OracleArtifactSHA256), ...
    hashExpression, "once"))), ...
    "Every independent row must identify a real SHA-256 oracle artifact.");
assert(all(strlength(independent.OracleImplementation) > 0 ...
    & strlength(independent.OracleVersion) > 0), ...
    "Every independent row must identify its oracle implementation/version.");
receiver = independent(lower(independent.VectorFamily) ...
    == "receiver_chain", :);
assert(height(receiver) == 1 ...
        && receiver.CaseID == "EXT-RX-SISO-16QAM-BG1-001" ...
        && receiver.OracleImplementation ...
            == "py3gpp/external_pdsch_waveform" ...
        && contains(receiver.ComparedField, "frozen waveform") ...
        && ~contains(lower(receiver.OracleImplementation), "production") ...
        && ~contains(lower(receiver.OracleImplementation), ...
            "prefix_identity"), ...
    ["Receiver-chain evidence must consume the frozen external waveform; " ...
     "a production TX/RX loop is not an independent vector."]);

layers = tables.pdsch_layer_codeword_map;
assert(isequal(sort(unique(str2double(layers.Rank))), (1:8).') ...
    && height(layers) == 36 ...
    && all(str2double(layers.MismatchCount) == 0), ...
    "Rank-one through rank-eight layer evidence is incomplete.");
precoding = tables.pdsch_precoding_application;
assert(any(contains(lower(precoding.Mode), "wideband")) ...
    && any(contains(lower(precoding.Mode), "prg")) ...
    && all(precoding.MatrixDigest == precoding.AppliedMatrixDigest) ...
    && all(str2double(precoding.TXApplicationCount) > 0) ...
    && all(str2double(precoding.RXApplicationCount) > 0), ...
    "Precoder execution/application evidence is incomplete.");

harq = tables.pdsch_harq_trials;
sequence = harq(harq.CaseID == "HARQ-RV-SEQUENCE", :);
assert(height(sequence) == 4 ...
    && isequal(str2double(sequence.RV), [0;2;3;1]) ...
    && any(localTruth(sequence.Combined)) ...
    && all(localTruth(sequence.TBCRCOK)) ...
    && all(str2double(sequence.TBS) == 40) ...
    && numel(unique(sequence.TBIdentity)) == 1 ...
    && strlength(sequence.TBIdentity(1)) == 64 ...
    && numel(unique(sequence.SoftBufferInputDigest)) == 4 ...
    && numel(unique(sequence.SoftBufferOutputDigest)) == 4, ...
    "The observed RV 0/2/3/1 HARQ sequence is incomplete.");
dual = harq(harq.CaseID == "HARQ-CW2-SEQUENCE", :);
assert(height(dual) == 4 ...
        && isequal(sort(unique(str2double(dual.Codeword))), [0;1]) ...
        && nnz(localTruth(dual.Combined)) == 2 ...
        && all(localTruth(dual.TBCRCOK)) ...
        && all(strlength(dual.TBIdentity) == 64), ...
    ["Dual-codeword HARQ evidence must come from two canonical " ...
    "codeword-specific TX/RX observations and their retransmissions."]);
harqIndependent = independent( ...
    lower(independent.VectorFamily) == "harq_combining", :);
assert(height(harqIndependent) == 1 ...
        && contains(lower(harqIndependent.ComparedField), ...
            "canonical receiver") ...
        && harqIndependent.OracleImplementation ...
            == "sixgr.pdsch.oracle.HARQCombiningSpec", ...
    "HARQ independent evidence must identify canonical receiver LLR input.");

negative = tables.pdsch_negative_tests;
assert(height(negative) == 106, ...
    "Every frozen negative case must execute exactly once.");
assert(all(strlength(negative.ExpectedErrorIdentifier) > 0) ...
    && all(negative.ExpectedErrorIdentifier ...
        == negative.ActualErrorIdentifier) ...
    && all(~localTruth(negative.WaveformGenerated)), ...
    "Negative evidence must contain exact typed IDs and no waveform.");
tbsNegative = negative(negative.TestKind ...
    == "tbs_independent_scalar_input_contract", :);
assert(height(tbsNegative) == 5 ...
        && all(startsWith(tbsNegative.ActualErrorIdentifier, ...
            "sixgr:pdsch:PDSCHTBSScalarInputValidator:")) ...
        && all(~contains(tbsNegative.ActualErrorIdentifier, ":oracle:")), ...
    "TBS negative evidence must invoke the production scalar trust boundary.");
assert(nnz(negative.TestKind == "assignment_resolution") == 16 ...
    && nnz(negative.TestKind == "dmrs_symbol_configuration") == 42 ...
    && nnz(negative.TestKind == "dmrs_port_table") == 18 ...
    && nnz(negative.TestKind == "ptrs_presence") == 3 ...
    && nnz(negative.TestKind == "reserved_re_union") == 3 ...
    && nnz(negative.TestKind ...
        == "tbs_independent_scalar_input_contract") == 5 ...
    && nnz(negative.TestKind == "qam_modulation") == 4 ...
    && nnz(negative.TestKind == "codeword_layer_mapping") == 4 ...
    && nnz(negative.TestKind == "precoder_bundle") == 6 ...
    && nnz(negative.TestKind == "harq_transition") == 5, ...
    "Executed negative-family counts differ from the frozen pack.");

fprintf([ ...
    'PDSCH phase evidence: 11 exact-contract tables, ' ...
    '16 mandatory independent families, 106/106 typed negatives pass.\n']);
ok = true;
end

function value = localReadStrings(path)
options = detectImportOptions(path, ...
    "Delimiter", ",", "TextType", "string", ...
    "VariableNamingRule", "preserve");
options = setvartype(options, options.VariableNames, "string");
value = readtable(path, options);
for i = 1:width(value)
    name = value.Properties.VariableNames{i};
    column = string(value.(name));
    column(ismissing(column)) = "";
    value.(name) = column;
end
end

function value = localTruth(raw)
token = upper(strtrim(string(raw)));
value = ismember(token, ["1","TRUE","YES","PASS"]);
end
