function ok = testSchedulerAMCNoFixedMCSFallback()
%TESTSCHEDULERAMCNOFIXEDMCSFALLBACK AMC must not promote configured MCS.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "lls_3gpp_rel20_anchor_4ghz_100mhz_waveform_honest_200ue_1frame.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.mode", "amc");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.dlPolicy", "baseline");
cfg = sixgr.util.structSet(cfg, "phy.linkAdaptation.rankPolicy", "adaptive");
cfg = sixgr.util.structSet(cfg, "phy.pdsch.mcsIndex", 26);
% This is an isolated grant/waveform unit campaign without geometry and
% receiver-power context, so its SNR argument explicitly owns AWGN.
cfg = sixgr.util.structSet(cfg, "run.noiseOperatingMode", ...
    "standalone_awgn_snr_argument");
% This isolated scheduler fixture deliberately changes the canonical
% authority as well as compatibility aliases. Production code is
% runtime-authority-first; mutating only a stale legacy alias must not
% influence scheduling.
cfg = sixgr.util.structSet(cfg, "runtime.link_adaptation.Mode", "amc");
cfg = sixgr.util.structSet(cfg, "runtime.link_adaptation.DLPolicy", "baseline");
