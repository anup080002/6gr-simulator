cfg = sixgr.util.structSet(cfg, "phy.pdsch.mappingType", "A");
cfg = sixgr.util.structSet(cfg, "phy.pusch.mappingType", "A");
cfg = sixgr.util.structSet(cfg, "phy.pdsch.dmrs.portSet", 0);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.dmrs.nPorts", 1);
cfg = sixgr.util.structSet(cfg, "phy.pdsch.executionProfile", "scheduler_truth");
