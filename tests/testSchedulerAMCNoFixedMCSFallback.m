ollaScheduler.updateAfterRx(struct("RNTI", 9001, "TBSBits", 2048, "Ack", false));
[~, ~, ~, amcAfterNack] = ollaScheduler.selectAMC(ueOLLA);
assert(logical(amcAfterNack.OuterLoopApplied) && double(amcAfterNack.OLLAUpdateCount) >= 1, ...
    "Scheduler OLLA must be applied only after ACK/NACK feedback updates the per-UE loop state.");
assert(double(amcAfterNack.MCSIndex) < double(amcBeforeNack.MCSIndex), ...
    "A scheduler-side NACK must reduce the next CQI-table MCS through the OLLA delta.");
[deltaBeforeRetxAck, countBeforeRetxAck] = ollaScheduler.getOLLAMCSDelta(9001);
ollaScheduler.updateAfterRx(struct( ...
    "RNTI", 9001, "TBSBits", 2048, "Ack", true, ...
    "RV", 2, "IsRetransmission", true));
[deltaAfterRetxAck, countAfterRetxAck] = ollaScheduler.getOLLAMCSDelta(9001);
assert(abs(double(deltaAfterRetxAck) - double(deltaBeforeRetxAck)) < 1e-12 && ...
    double(countAfterRetxAck) == double(countBeforeRetxAck), ...
    "HARQ retransmission ACK must not relax the first-transmission OLLA backoff.");
ollaScheduler.updateAfterRx(struct( ...
    "RNTI", 9001, "TBSBits", 2048, "Ack", true, ...
    "RV", 0, "IsRetransmission", false));
[deltaAfterNewDataAck, countAfterNewDataAck] = ollaScheduler.getOLLAMCSDelta(9001);
assert(double(deltaAfterNewDataAck) > double(deltaAfterRetxAck) && ...
    double(countAfterNewDataAck) == double(countAfterRetxAck) + 1, ...
    "A new-data RV0 ACK must still update the first-transmission OLLA loop.");

