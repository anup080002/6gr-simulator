function ok = testPrecoderDigestEvidenceDomains()
%TESTPRECODERDIGESTEVIDENCEDOMAINS Prevent logical/physical hash mixing.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

logicalMatrix = [1 0; 0 1] ./ sqrt(2);
elementMatrix = [logicalMatrix; logicalMatrix] ./ sqrt(2);
logicalDigest = string(sixgr.phy.mimo.MatrixContract.digest(logicalMatrix));
elementDigest = string(sixgr.phy.mimo.MatrixContract.digest(elementMatrix));

grant = struct("PHYGrant", struct( ...
    "GrantContextId", "UL|cell=1|ue=1|frame=1|slot=5", ...
    "PrecodingState", struct( ...
        "SelectedMatrixSHA256", logicalDigest, ...
        "AppliedMatrixSHA256", elementDigest, ...
        "WaveformDomain", "physical_element")));
precodeInfo = struct( ...
    "MatrixPorts", elementMatrix, ...
    "SelectedMatrixSHA256", logicalDigest, ...
    "AppliedMatrixSHA256", elementDigest, ...
    "WaveformDomain", "physical_element", ...
    "HybridElementDomainApplied", true);

evidence = sixgr.phy.grant.resolvePrecoderDigestEvidence(grant, precodeInfo);
assert(evidence.RequestedPrecoderSHA256 == elementDigest && ...
    evidence.AppliedPrecoderSHA256 == elementDigest && ...
    evidence.AppliedPrecoderMatrixSHA256 == elementDigest, ...
    "Requested/applied digest evidence must compare the frozen and actual physical matrices.");
assert(evidence.RequestedPrecoderSHA256 ~= logicalDigest, ...
    "The logical TPMI/codebook digest must not be mislabeled as a waveform-domain request.");
assert(evidence.PrecoderDigestDomain == "physical_element" && ...
    evidence.FrozenGrantContextId == "UL|cell=1|ue=1|frame=1|slot=5", ...
    "Digest evidence must expose its waveform domain and frozen grant identity.");

bad = precodeInfo;
bad.MatrixPorts = [];
bad.AppliedMatrixSHA256 = "not-a-digest";
localAssertThrows(@() sixgr.phy.grant.resolvePrecoderDigestEvidence(grant, bad), ...
    "sixgr:phy:grant:InvalidPrecoderDigest");
noRequest=sixgr.phy.grant.resolvePrecoderDigestEvidence(struct(),precodeInfo);
assert(strlength(noRequest.RequestedPrecoderSHA256)==0 && noRequest.AppliedPrecoderSHA256==elementDigest, ...
    'Applied waveform evidence cannot manufacture a requested digest or a false requested/applied match.');
requestedOnly=grant;
requestedOnly.AppliedPrecoderSHA256=elementDigest;
requestedOnly.AppliedPrecoderMatrixSHA256=elementDigest;
noTransmitter=sixgr.phy.grant.resolvePrecoderDigestEvidence(requestedOnly,struct());
assert(noTransmitter.RequestedPrecoderSHA256==elementDigest && strlength(noTransmitter.AppliedPrecoderSHA256)==0, ...
    'Grant claims cannot substitute for an absent transmitter-applied matrix.');
ok = true;
end

function localAssertThrows(fh, expectedIdentifier)
try
    fh();
catch ME
    assert(strcmp(ME.identifier, expectedIdentifier), ...
        "Expected %s, got %s: %s", expectedIdentifier, ME.identifier, ME.message);
    return;
end
error("ExpectedException:notThrown", "Expected %s to be thrown.", expectedIdentifier);
end
