function ok = testPDSCH6GRMultiCodewordStudy()
%TESTPDSCH6GRMULTICODEWORDSTUDY Study facade must preserve PDSCH two-codeword rows.

setup6GRSimToolkit("Verbose", false);
cfg = localCfg();
matrix = struct("ScenarioID","rank6","SNRdB",80,"FDRAType","type1_riv", ...
    "StartSymbol",2,"NumSymbols",8,"ChannelModel","AWGN","DelaySpread_ns",30, ...
    "Rank",6,"RepetitionMode","none","PTRSMode","disabled","SpeedKmh",3, ...
    "DMRSAdditionalPosition",1,"NumTrials",1);
out = sixgr.pdsch.runPDSCHStudyLLS(cfg, "ScenarioMatrix", matrix, ...
    "WriteOutputs", false, "Verbose", false);

assert(height(out.TrialLevelResults) == 1 && double(out.TrialLevelResults.num_codewords(1)) == 2, ...
    "Rank-6 study trial row must report two materialized codewords.");
assert(height(out.CodewordLevelResults) == 2 && isequal(double(out.CodewordLevelResults.codeword_index(:).'), [0 1]), ...
    "Rank-6 study codeword table must export one row per codeword.");
assert(all(double(out.CodewordLevelResults.tb_size_bits) > 0) && all(double(out.CodewordLevelResults.coded_bits) > 0), ...
    "Rank-6 study codeword rows must carry per-codeword TBS and coded-bit counts.");
assert(any(double(out.LayerMappingTrace.CodewordIndex) == 1), ...
    "Rank-6 study layer trace must include codeword 1 layers.");

ok = true;
end

