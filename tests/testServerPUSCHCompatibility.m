function ok=testServerPUSCHCompatibility()
% Required API probe, not a promise that every test/scenario supports a release.
setup6GRSimToolkit('Verbose',false);
p=nrPUSCHConfig();
fprintf('SERVER_PUSCH_CAPABILITY MATLAB=%s NumCodewords=%d nrULSCHDemultiplex=%d\n', ...
    version('-release'),isprop(p,'NumCodewords'),exist('nrULSCHDemultiplex','file')~=0);
assert(isprop(p,'NumCodewords'),'sixgr:tests:UnsupportedPUSCHCodewordAPI', ...
    ['Current PUSCH/UCI code requires nrPUSCHConfig.NumCodewords (R2024a or later). ' ...
    'R2023b is not qualified for this implementation; do not silently reduce features. ' ...
    'R2026a is the locally tested reference.']);
assert(exist('nrULSCHDemultiplex','file')~=0 && exist('nrUCIEncode','file')~=0 && ...
    exist('nrUCIDecode','file')~=0,'sixgr:tests:MissingPUSCHUCIAPI', ...
    'Install the licensed 5G Toolbox APIs required by this implementation.');
fprintf('SERVER_PUSCH_COMPATIBILITY_PROBE_PASS not_full_release_qualification=1\n');
ok=true;
end
