function ok = testCanonicalRuntimeControlTrialSeparation()
%TESTCANONICALRUNTIMECONTROLTRIALSEPARATION Keep strict campaigns sidecar-only.

runtime = table([1;2], ["CoupledTruthRuntime.applySRSTrial"; ...
    "CoupledTruthRuntime.applySRSTrial"], ...
    ["canonical_control_reference_signal_runtime_evidence"; ...
    "canonical_control_reference_signal_runtime_evidence"], ...
    ["control_reference_signal_runtime_evidence"; ...
    "control_reference_signal_runtime_evidence"], ...
    'VariableNames', {'Trial','RuntimeStateConsumer','ArtifactClass','ValueRole'});
strict = table([3;4], ["";""], ["strict_validation";"strict_validation"], ...
    ["strict_waveform_validation";"strict_waveform_validation"], ...
    'VariableNames', runtime.Properties.VariableNames);
mixed = [runtime; strict];

selected = sixgr.truth.selectCanonicalRuntimeControlTrials(mixed, "srs");
assert(height(selected) == 2 && isequal(selected.Trial, [1;2]), ...
    "Supplemental strict trials leaked into canonical runtime selection.");
assert(isempty(sixgr.truth.selectCanonicalRuntimeControlTrials(strict, "srs")), ...
    "Strict-only validation rows were mislabeled as coupled runtime truth.");

bySource = table(5, "air_interface/csv/pdcch_trials.csv", ...
    'VariableNames', {'Trial','SourceArtifact'});
assert(height(sixgr.truth.selectCanonicalRuntimeControlTrials( ...
    bySource, "pdcch")) == 1, ...
    "Canonical SourceArtifact lineage was not recognized.");
ok = true;
end
