function ok=testInPathChannelRFNoSupplementalWaveforms(runFolder)
% In-path validation is a reducer, not a second waveform execution.
% This negative fixture has no physical trial rows and must not qualify.
setup6GRSimToolkit('Verbose',false);
scenario=sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    'simulator','configs','scenarios', ...
    'lls_tdd_5mhz_rank2_shared_awgn_20db_saturated.yaml'));
cfg=sixgr.lls6g.buildInternalConfig(scenario,tempname);
prior=rng;
cleanup=onCleanup(@()rng(prior));
rng(714305,'twister');
before=rng;
caught="";
try
    sixgr.channel.runStrictChannelRFValidation(cfg, ...
        'RunId','missing_in_path_fixture', ...
        'ScenarioName','missing_in_path_fixture', ...
        'ExecutionID','declared_negative_fixture_not_physical_execution', ...
        'ScenarioConfigHash',string(cfg.meta.configHash), ...
        'RuntimeTrials',struct(),'WriteArtifacts',false);
catch cause
    caught=string(cause.identifier);
end
assert(caught=="sixgr:channel:MissingInPathRuntimeTrials", ...
    'testInPathChannelRFNoSupplementalWaveforms:WrongFailure', ...
    'Missing runtime evidence must fail at the in-path evidence boundary, not a supplemental probe: %s',caught);
assert(isequal(rng,before), ...
    'testInPathChannelRFNoSupplementalWaveforms:ProbeRNGMutation', ...
    'An in-path evidence request must not reset/consume global waveform RNG state.');
if nargin>0
    localVerifyRetainedRun(runFolder);
end
fprintf('IN_PATH_CHANNEL_RF_NO_SUPPLEMENTAL_WAVEFORMS_PASS negative evidence-only fixture; physical_qualification=0\n');
ok=true;
end

function localVerifyRetainedRun(runFolder)
% Optional read-only positive check against actual retained execution.
% No authored rows, trial mutation, waveform replay or artifact publication.
[scenario,authority]=sixgr.truth.resolveRecoveryScenarioConfig(runFolder,struct());
cfg=sixgr.lls6g.buildInternalConfig(scenario,runFolder);
layout=sixgr.report.resultLayout(runFolder);
paths=[string(fullfile(layout.AirInterfaceCSVDir,'dl_pdsch_trials.csv')); ...
    string(fullfile(layout.AirInterfaceCSVDir,'ul_pusch_trials.csv'))];
raw=struct(); hashes=strings(2,1); directions=["DL","UL"];
for k=1:2
    hashes(k)=string(sixgr.phy.waveform.WaveformHash.file(paths(k)));
    raw.(directions(k))=sixgr.util.csvReadTable(paths(k),'TextType','string');
    assert(~isempty(raw.(directions(k))),'Both directions require retained physical rows.');
end
id=raw.DL(1,:);
for direction=directions
    rows=raw.(direction);
    assert(all(string(rows.ExecutionID)==string(id.ExecutionID)) && ...
        all(string(rows.ConfigHash)==string(authority.ResolvedConfigHash)) && ...
        all(string(rows.RunID)==string(id.RunID)) && ...
        all(string(rows.ScenarioID)==string(id.ScenarioID)));
end
status=profile('status');
assert(strcmp(status.ProfilerStatus,'off'), ...
    'Do not replace an active caller-owned profiler session.');
profile on;
cleanup=onCleanup(@()profile('off'));
before=rng;
result=sixgr.channel.runStrictChannelRFValidation(cfg, ...
    'RunFolder',runFolder,'RunId',string(id.RunID), ...
    'ScenarioName',string(id.ScenarioID),'ExecutionID',string(id.ExecutionID), ...
    'ScenarioConfigHash',string(id.ConfigHash), ...
    'RuntimeTrials',raw,'WriteArtifacts',false);
assert(isequal(rng,before),'Retained evidence reduction must preserve global RNG state.');
profile off;
calls=profile('info');
names=string({calls.FunctionTable.FunctionName});
for forbidden=["localQPSKWaveform","localChannelRealizationEvidence", ...
        "localInterferenceEvidence","localThermalNoiseEvidence", ...
        "applyRFImpairmentChain","applyRuntimeChannel", ...
        "runDLPDSCHThroughput","runULPUSCHThroughput"]
    assert(~any(contains(names,forbidden)), ...
        'testInPathChannelRFNoSupplementalWaveforms:UnexpectedExecution', ...
        'Retained evidence reduction executed %s.',forbidden);
end
assert(result.StrictOk && result.EvidenceScope=="in_path" && ...
    ~result.LaunchedSupplementalWaveform && ...
    height(result.ChannelRealizations)==height(raw.DL)+height(raw.UL));
% Verified coefficient archives are keyed by the retained observation ID,
% not the legacy processor-interval ChannelRealizationId. Require the exact
% archive identity AND its content hash; do not accept the weaker legacy row.
assert(isequal(string(result.ChannelRealizations.ChannelRealizationId), ...
    [string(raw.DL.ChannelObservationID);string(raw.UL.ChannelObservationID)]) && ...
    isequal(string(result.ChannelRealizations.CoefficientMATFileSHA256), ...
    [string(raw.DL.ChannelObservationMATFileSHA256);string(raw.UL.ChannelObservationMATFileSHA256)]), ...
    'The reducer must retain the exact verified observation/archive identity.');
assert(isequaln(result.EVMMeasurements.EVMPercent, ...
    100*[double(raw.DL.EVM_rms);double(raw.UL.EVM_rms)]), ...
    'Only retained receiver EVM may populate in-path output.');
for k=1:2
    assert(string(sixgr.phy.waveform.WaveformHash.file(paths(k)))==hashes(k), ...
        'Read-only reduction changed a retained primary trial CSV.');
end
fprintf('RETAINED_CHANNEL_RF_REDUCTION_PASS DL=%d UL=%d no_supplemental_waveforms=1\n', ...
    height(raw.DL),height(raw.UL));
clear cleanup;
end
