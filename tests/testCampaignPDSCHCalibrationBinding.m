function ok = testCampaignPDSCHCalibrationBinding()
%TESTCAMPAIGNPDSCHCALIBRATIONBINDING Guard production campaign ownership.

repoRoot = fileparts(fileparts(mfilename("fullpath")));
source = fileread(fullfile(repoRoot, "sixgr_run_3gpp_full_campaign.m"));

txCalls = regexp(source, ...
    '(?s)sixgr\.phy\.dl\.PDSCH_Tx\s*\(.*?\);', "match");
rxCalls = regexp(source, ...
    '(?s)sixgr\.phy\.dl\.PDSCH_Rx\s*\(.*?\);', "match");
throughputCalls = regexp(source, ...
    '(?s)sixgr\.link\.runDLPDSCHThroughput\s*\(.*?\);', "match");

assert(numel(txCalls) == 6, ...
    "Campaign PDSCH TX caller inventory changed; audit every new caller.");
assert(numel(rxCalls) == 4, ...
    "Campaign PDSCH RX caller inventory changed; audit every new caller.");
assert(numel(throughputCalls) == 4, ...
    "Campaign DL-throughput caller inventory changed; audit every new caller.");

for callIndex = 1:numel(txCalls)
    localAssertToken(txCalls{callIndex}, ...
        '"ExecutionProfile"\s*,\s*"phy_calibration"', ...
        "Every campaign PDSCH TX call must name phy_calibration.");
end
for callIndex = 1:numel(rxCalls)
    localAssertToken(rxCalls{callIndex}, ...
        '"CodingPlan"\s*,\s*tx\.CodingPlans', ...
        "Every campaign PDSCH RX call must consume the exact TX coding plan.");
    localAssertToken(rxCalls{callIndex}, ...
        '"ExecutionProfile"\s*,\s*"phy_calibration"', ...
        "Every campaign PDSCH RX call must name phy_calibration.");
end
for callIndex = 1:numel(throughputCalls)
    localAssertToken(throughputCalls{callIndex}, ...
        '"ExecutionProfile"\s*,\s*"phy_calibration"', ...
        "Every campaign DL-throughput call must name phy_calibration.");
end

localAssertToken(source, ...
    '"phy\.pdsch\.mcsTablePerCodeword"\s*,\s*tableTokens', ...
    "Campaign calibration must own an MCS table token per codeword.");
localAssertToken(source, ...
    '"phy\.pdsch\.mcsIndexPerCodeword"\s*,\s*codewordIndices', ...
    "Campaign calibration must own a typed index per codeword.");
localAssertToken(source, ...
    'tableTokens\s*=\s*repmat\("calibration_explicit"', ...
    "Campaign calibration must use the exact, non-nearest MCS identity token.");
localAssertToken(source, ...
    'codewordIndices\s*=\s*0:\(numCodewords\s*-\s*1\)', ...
    "Campaign calibration MCS indices must identify zero-based codewords.");

fprintf(['Campaign PDSCH calibration binding: 6/6 TX profiles, ' ...
    '4/4 RX coding-plan/profile bindings, 4/4 throughput profiles.\n']);
ok = true;
end

function localAssertToken(source, pattern, message)
assert(~isempty(regexp(source, pattern, "once")), message);
end
