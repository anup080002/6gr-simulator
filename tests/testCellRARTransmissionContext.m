function [ok,fixture]=testCellRARTransmissionContext()
% Declared detector-result fixture, real selected common geometry/DCI codec.
% No detector, RAR waveform, UE receiver or access completion is claimed.
repo=fileparts(fileparts(mfilename('fullpath')));
s=sixgr.lls6g.config.loadScenarioConfig(fullfile(repo,'simulator','configs','scenarios', ...
    'lls_tdd_n40_20mhz_64txru_4rx_cdlc100_impaired.yaml'));
cfg=sixgr.lls6g.buildInternalConfig(s,tempname);
c=sixgr.phy.grid.makeCarrier(cfg); info=nrOFDMInfo(c);
calendar=sixgr.truth.buildCellPRACHReceiveCalendar(cfg,1,struct( ...
    'SampleRateHz',info.SampleRate,'NumReceiveAntennas',64,'FilterDelaySamples',7,'FilterTailSamples',31));
windows=sixgr.truth.planCellPRACHReceiveWindows(calendar,0,info.SampleRate*0.03);
p=windows{1}; row=p.OriginalNativeRow;
ordinal=mod(p.OccasionOrdinal1-1,height(calendar.Native.Occasions)* ...
    calendar.Association.AssociationPeriodConfigurationCount)+1;
map=calendar.Association.Mapping; hit=find(map.Ordinal==ordinal,1);
assert(~isempty(hit));
det=struct('Detected',true,'DetectedPreambleIndex',map.CBPreambleStart0(hit), ...
    'PropagationTimingOffsetSamples',3,'TimingOffsetSamples',10, ...
    'AssociatedSSBIndex0',map.SSBIndex0(hit),'ServingCell',1,'CellId',c.NCellID, ...
    'PRACHAbsoluteSlot',row.AbsoluteSlot+p.NativePeriodIndex0*calendar.Native.PeriodCarrierSlots, ...
    'PRACHOccasionSymbol',row.RARNTISymbolIndex,'PRACHFrequencyIndex',row.FrequencyIndex, ...
    'RARNTI',p.ExpectedRARNTI,'SampleRateHz',info.SampleRate);
r=struct('ContractVersion',"completed_cell_PRACH_receiver/v1", ...
    'CellCalendarSHA256',calendar.SHA256,'ReceiverExecuted',true,'ServingCell',1, ...
    'PhysicalCellID',c.NCellID,'AdmittedDetections',det,'Plan',p, ...
    'CompletedAtSample',p.ReceiveEndSampleExclusive, ...
    'FixtureBoundary',"declared_detector_result_not_executed_RF"); r.SHA256=hash(r);
before=rng;
[txcfg,ra,policy]=sixgr.truth.buildCellRARTransmissionContext(cfg,calendar,r);
assert(isequal(before,rng) && ra.ResponseSchedulable && ra.UEId==0 && ...
    ra.RARDCIReference.FrequencyReferenceSource=="original_gNB_configured_mib_coreset0" && ...
    ~isfield(txcfg,'UECommonCellConfiguration') && ...
    ra.AssociatedSSBIndex0==det.AssociatedSSBIndex0 && ra.Msg3Slot>ra.Msg2Slot && ...
    ra.ReceiverCompletedAtSample==p.ReceiveEndSampleExclusive && ...
    sixgr.phy.frame.slotStartSample(c,ra.Msg2Slot,info.SampleRate)>=r.CompletedAtSample);
schedule=sixgr.phy.ra.scheduleMsg2RAR(ra);
assert(schedule.RNTI==p.ExpectedRARNTI && schedule.PDSCH.NumLayers==1);
assert(ra.RARDCIReference.AuthorityRole=="original_gNB_transmitter_configuration");
missingRole=rmfield(ra.RARDCIReference,'AuthorityRole');
reject(@()sixgr.phy.pdcch.RARDCIContext.create(missingRole,ra.RARNTI), ...
    'sixgr:phy:pdcch:invalid_rar_dci_context');
reject(@()sixgr.phy.ra.RARReceiveWindow(txcfg,ra),'sixgr:phy:ra:GNBConfigurationAtUEReceiver');
reject(@()sixgr.phy.ra.recoverMsg2RAR([],txcfg,ra,struct(),struct()), ...
    'sixgr:phy:ra:GNBConfigurationAtUEReceiver');
reject(@()sixgr.phy.ra.recoverMsg2RAR([],cfg,ra,struct(),struct()), ...
    'sixgr:phy:ra:GNBConfigurationAtUEReceiver');
assert(policy.Msg3PUSCH.NLayers==1 && ~policy.Msg3PUSCH.EnablePTRS);
changed=cfg; changed.random_access.preamble_index=63;
changed.random_access.associated_ssb_index=7;
changed.random_access.temp_crnti=999; changed.random_access.final_crnti=1000;
[~,same]=sixgr.truth.buildCellRARTransmissionContext(changed,calendar,r);
assert(isequaln(same,ra),'UE intentions cannot select the cell response or its common DCI reference.');
bad=r; bad.CompletedAtSample=bad.CompletedAtSample+1;
reject(@()sixgr.truth.buildCellRARTransmissionContext(cfg,calendar,bad), ...
    'sixgr:truth:CellRAROriginalReceiverRequired');
badcfg=txcfg; badcfg.UECommonCellConfiguration=struct('Source',"forged_received");
reject(@()sixgr.phy.ra.resolveRARDCIReference(badcfg),'sixgr:phy:ra:MixedCommonControlAuthority');
reject(@()sixgr.phy.ra.resolveRARCommonControl(badcfg,c),'sixgr:phy:ra:MixedCommonControlAuthority');
ok=true;
fixture=struct('Config',cfg,'TXConfig',txcfg,'RAContext',ra,'Policy',policy, ...
    'Calendar',calendar,'DeclaredReceiverReceipt',r);
fprintf('CELL_RAR_CONTEXT_PASS declared_detector_boundary=1 Msg2=%d Msg3=%d RFexecutions=0\n',ra.Msg2Slot,ra.Msg3Slot);
end
function value=hash(x)
value=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(x))));
end
function reject(f,id)
try, f(); catch e, assert(string(e.identifier)==id,'Expected %s, got %s',id,e.identifier); return; end
error('test:CellRARContextGuardMissing','Expected %s.',id);
end
