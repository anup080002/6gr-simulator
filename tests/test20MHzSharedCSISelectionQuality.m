function ok=test20MHzSharedCSISelectionQuality(outputRoot)
% One configured n40 CSI-RS occasion on the actual 64x4 CDL/RF sample clock.
% This deliberately exercises only the CSI transmitter/receiver/audit path:
% no acquired access, received UCI, later PDSCH or full-run claim is made.
setup6GRSimToolkit('Verbose',false);
if nargin<1, outputRoot=fullfile(pwd,'results','validation','n40_shared_csi_selection'); end
source=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_tdd_n40_20mhz_64txru_4rx_cdlc100_impaired.yaml');
prior=rng; restore=onCleanup(@()rng(prior)); %#ok<NASGU>
rng(double(source.get('simulation.random_seed')),'twister');
folder=fullfile(outputRoot,char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(folder); fprintf('N40_SHARED_CSI_SELECTION_ROOT=%s\n',folder);
% Establish real lifecycle identity before any queue/archive write, as the
% production runner does. This remains a bounded component execution, not
% a completed scenario or a populated campaign assembled after reception.
[~,executionTag]=fileparts(folder);
identity=sixgr.runtime.resolveExecutionIdentity(folder, ...
    "n40_shared_csi_component_"+string(executionTag),string(source.ConfigHash));
cfg=sixgr.lls6g.buildInternalConfig(source,folder); cfg.run.rootRunFolder=folder;
cfg.run.runTag=char(identity.RunID);
cfg.run.executionID=char(identity.ExecutionID);
cfg.run.scenarioID=char(string(source.ScenarioID));
cfg.meta.executionID=char(identity.ExecutionID);
cfg.meta.configHash=char(identity.ConfigHash);
cfg.meta.scenarioID=char(string(source.ScenarioID));
assert(cfg.measurements.csiSelectionQuality.Enabled && ...
    cfg.phy.carrier.NSizeGrid==51 && cfg.phy.nTxAnt==64 && cfg.phy.nRxAnt==4);
scope=struct('SourceScenario',string(source.ConfigPath), ...
    'Scope',"one_configured_CSI_RS_occasion_on_actual_shared_CDL_RF_clock", ...
    'AccessExecuted',false,'UCIDeliveryExecuted',false,'DataExecuted',false, ...
    'ScenarioAccepted',false,'StatisticallyQualified',false, ...
    'ExecutionIdentity',identity,'SourceSnapshot',localSnapshot());
resolvedScenario=source.toStruct();
sixgr.util.jsonWrite(fullfile(folder,'meta','resolved_config.json'),resolvedScenario);
save(fullfile(folder,'configuration.mat'),'cfg','scope','resolvedScenario');
metadataSNR=double(source.get('simulation.snr_db')); % Metadata, not thermal-noise authority.
multi=struct('Enabled',true,'NumUsers',1,'RNTIStart',1,'ExecutionModel','slot_coupled_truth');
state=sixgr.truth.CoupledTruthRuntime.initialize(cfg,fullfile(folder,'air_interface'),multi,struct(),cfg.run.totalSlots);
state=sixgr.truth.CoupledTruthRuntime.advanceFrame(state,cfg,multi,1,metadataSNR);
state=sixgr.truth.CoupledTruthRuntime.startSlot(state,cfg,'DL',1,1,1,cfg.run.totalSlots,metadataSNR);
state.CurrentServingIdx(:)=1;
[state,owner]=sixgr.truth.CoupledWaveformStream.initialize(state,cfg,{cfg});
assert(owner.SampleRateHz==30.72e6);
firstSlot=double(cfg.phy.csirs.offset_slots)+1;
assert(isscalar(firstSlot) && firstSlot>=1 && firstSlot<=cfg.run.totalSlots);
received=0; queuedCount=0;
for slot=1:firstSlot+1
    [slotCfg,timeline]=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,slot);
    state=sixgr.truth.CoupledTruthRuntime.beginSlot( ...
        state,slotCfg,slotCfg,1,'DL',1,1,slot,cfg.run.totalSlots,metadataSNR);
    if slot==firstSlot
        [dl,state]=sixgr.truth.CoupledTruthRuntime.applyUserContext(slotCfg,state,1,'DL');
        [state,queued,reason,prepared]=sixgr.truth.queueSharedPeriodicCSIRS( ...
            state,dl,1,slot,timeline.FrameIndexOneBased,1,1,metadataSNR);
        assert(queued,'test:N40CSIQueue','Configured CSI occasion was not queued: %s',reason);
        assert(prepared.NumPhysicalTransmitAntennas==64 && ...
            prepared.Carrier.NSizeGrid==51 && prepared.SampleRateHz==30.72e6);
        queuedCount=queuedCount+1;
    end
    state=owner.advanceSlot(state,slotCfg,@consume);
    fprintf('N40_SHARED_CSI_SELECTION_SLOT=%d/%d received=%d\n',slot,firstSlot+1,received);
end
assert(received==1 && queuedCount==1 && ~owner.hasPending('CSIRS',1));
row=state.ControlTrials.CSIRS;
assert(height(row)==1 && row.Slot==firstSlot && row.CSISelectionQualityAvailable && ...
    row.NMSEScoringAvailable && row.ChannelNMSEAllResourcesMeasured && ...
    row.ChannelNMSEMeasuredResourceCount==8 && row.ChannelNMSEConfiguredResourceCount==8);
assert(row.RunID==identity.RunID && row.ExecutionID==identity.ExecutionID && ...
    row.ConfigHash==identity.ConfigHash && row.ScenarioID==string(source.ScenarioID) && ...
    row.RandomSeed==cfg.run.seed && row.ChannelSeed==cfg.channel.seed && ...
    row.SweepPointIndex==1 && row.ConfiguredSNR_dB==metadataSNR, ...
    'test:N40CSIPopulation','Retain actual pre-execution lifecycle and configured point identity.');
assert(isfinite(row.MeasurementRSRP_dBm) && isfinite(row.MeasurementRSSI_dBm) && ...
    ~row.MeasurementPowerReferenceNormalized && ...
    ~row.CSISelectionQualityStatisticallyQualified && ...
    ~row.CSISelectionQualityActualPDSCHPerformanceQualified);
audit=load(fullfile(folder,row.CSISelectionQualityMATFile));
assert(audit.Identity.MeasurementID==row.CSIMeasurementID && ...
    audit.Identity.ReceiverWindowID==row.ReceiverWindowID && ...
    audit.Identity.ObservationSHA256==row.ReceiverObservationSHA256 && ...
    audit.Summary.SelectedRank==row.RI && audit.Summary.SelectedPMI==row.PMI && ...
    audit.Inputs.Disturbance.WaveformAmplitudeUnit=="sqrt_mW" && ...
    audit.Inputs.Disturbance.SampleNoiseVarianceUnit=="mW" && ...
    audit.Inputs.Policy.PhysicalPowerUnit=="mW_scaled_grid_coefficient_squared_units" && ...
    audit.Inputs.Disturbance.NoiseReceipt.AdditionalNoiseExecutions==0 && ...
    audit.Inputs.Disturbance.NoiseReceipt.AdditionalChannelExecutions==0 && ...
    audit.Inputs.Disturbance.NoiseReceipt.AdditionalRFExecutions==0);
assert(isequal(double(audit.Inputs.Selection.RankDomain(:)).',[1 2 4]) && ...
    size(audit.Inputs.Reference.H,1)==4 && ...
    size(audit.Inputs.Reference.H,2)==4 && ...
    audit.Inputs.Reference.SupportScope=="selected_resource_pilot_union");
meta=struct('logical_run_id',identity.RunID,'run_id',1);
public=sixgr.truth.buildLLSPublicOutputTables(struct('csi_rs_table',row),sixgr.truth.llsOutputContract(),meta);
assert(public.csi_rs_runtime_event_table.CSISelectionQualityMATFile==row.CSISelectionQualityMATFile && ...
    public.csi_rs_runtime_event_table.CSISelectionQualityJointRegret_bpsHz==row.CSISelectionQualityJointRegret_bpsHz && ...
    public.csi_rs_runtime_event_table.SourceRunID==identity.RunID && ...
    isempty(public.csi_report_table),'test:N40CSIPublicScope', ...
    'Private UE selection-quality evidence must not become a received CSI-UCI report.');
csv=fullfile(folder,'air_interface','csv','csi_rs_trials.csv');
if ~isfolder(fileparts(csv)), mkdir(fileparts(csv)); end
sixgr.util.csvWriteTable(csv,row,'PreserveSchema',true);
persisted=sixgr.util.csvReadTable(csv,'TextType','string');
assert(persisted.CSISelectionQualityMATFile==row.CSISelectionQualityMATFile && ...
    persisted.ReceiverWindowID==row.ReceiverWindowID && ...
    persisted.ReceiverObservationSHA256==row.ReceiverObservationSHA256 && ...
    persisted.CSISelectionQualityIdentityJSON==row.CSISelectionQualityIdentityJSON);
for name=["MeasurementRSRP_dBm","MeasurementRSSI_dBm","NMSE_dB", ...
        "CSISelectionQualityJointRegret_bpsHz"]
    assert(abs(persisted.(name)-row.(name))<=1e-12*max(1,abs(row.(name))), ...
        'test:N40CSICSVArithmetic','Actual measured/scored %s changed during CSV publication.',name);
end
assert(isequaln(scope.SourceSnapshot,localSnapshot()), ...
    'test:N40CSISourceChanged','Production sources changed during the physical episode.');
save(fullfile(folder,'completion.mat'),'row','scope');
fprintf('N40_SHARED_CSI_SELECTION_PASS rank=%g PMI=%g CRI=%g NMSE=%g folder=%s\n', ...
    row.RI,row.PMI,row.CRI,row.NMSE_dB,folder);
ok=true;

    function next=consume(next,items)
        for item=reshape(items,1,[])
            assert(item.Kind=="CSIRS",'test:N40UnexpectedReceiver','Only CSI reception was scheduled.');
            p=item.Context.Prepared;
            [~,pre,~,replay,actual]=sixgr.truth.sharedObservationEvidence(item.Planes,p);
            % Reuse this received capture to prove post-hoc scoring neither
            % supplies oracle input nor changes the practical UE decision.
            plain=sixgr.phy.refsig.receiveCSIRSWaveform(p.Carrier,p.ReceiverConfig, ...
                actual.readComplete(),pre.readComplete(), ...
                [0 actual.EndSampleExclusive-actual.StartSample-p.NumSamples],replay);
            [plainCSI,~]=sixgr.phy.refsig.computeCSIRSFeedback(p.Carrier,p.ReceiverConfig,plain);
            clock=owner.Events.NextSampleIndex;
            [next,completed,rx,csi]=sixgr.truth.completeSharedCSIRSReception(next,item);
            assert(completed.ReceiverWindowID==string(item.ID), ...
                'test:N40CSIWindowIdentity','The actual completed parent window must survive measurement publication.');
            assert(isequaln(plainCSI,csi) && ...
                isequaln(plain.CSIRSChannelEstimate,rx.CSIRSChannelEstimate) && ...
                owner.Events.NextSampleIndex==clock && ...
                ~completed.ChannelNMSEReferenceUsedByReceiver, ...
                'test:N40CSIOracleIsolation','The independent audit changed the UE or advanced physical time.');
            assert(completed.ResultAvailableAtSample>=completed.ObservationEndSampleExclusive);
            received=received+1;
        end
    end
end

function snapshot=localSnapshot()
paths=["+sixgr/+lls6g/buildInternalConfig.m", ...
    "+sixgr/+truth/CoupledTruthRuntime.m","+sixgr/+truth/CoupledWaveformStream.m", ...
    "+sixgr/+truth/SharedWaveformPhysicalRuntime.m","+sixgr/+channel/ChannelFactory.m", ...
    "+sixgr/+rf/+runtime/RFImpairmentStream.m","+sixgr/+phy/+refsig/receiveCSIRSWaveform.m", ...
    "+sixgr/+phy/+refsig/receiveCSIRSFromGrid.m","+sixgr/+truth/completeSharedCSIRSReception.m", ...
    "+sixgr/+truth/bindSharedCSISelectionQuality.m","+sixgr/+truth/captureCSISelectionNoiseEvidence.m", ...
    "+sixgr/+truth/queueSharedPeriodicCSIRS.m","+sixgr/+truth/captureCSIObservationPopulation.m", ...
    "+sixgr/+truth/bindCSIObservationPopulation.m","+sixgr/+truth/exportCSISelectionQuality.m", ...
    "+sixgr/+truth/scoreSharedCSIRSChannel.m","+sixgr/+truth/scoreCSISelectionQuality.m", ...
    "tests/test20MHzSharedCSISelectionQuality.m"];
snapshot=struct('Path',cellstr(paths),'SHA256',cellstr(paths));
for k=1:numel(paths), snapshot(k).SHA256=char(sixgr.util.sha256File(paths(k))); end
end
