function ok = testPRACHRuntimeFailureEvidence()
% A failed producer supplies an execution error, not a measured PRACH row.
row = table("CRASH", "UL", 1, 0, true, false, false, ...
    "sixgr.phy.ra.runFourStepRA", "test:injected_channel_error", ...
    'VariableNames', {'Status','Direction','Slot','CRCPass','Crash', ...
    'RACompleted','PreambleDetected','RuntimeEvidenceSource','FailureReason'});
T = sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("PRACH", row);
assert(logical(T.Crash) && logical(T.FailureFlag) && ~logical(T.SuccessFlag), ...
    "Producer exceptions must remain failed execution evidence.");
assert(~logical(T.ControlObservationAvailable), ...
    "A producer exception must not claim an available receiver observation.");
assert(string(T.SourceClassification) == "execution_failed" && ...
    string(T.RuntimeMaterializationStatus) == "four_step_ra_runtime_failed", ...
    "A four-step RA exception must not be relabeled as a simplified PRACH execution.");
assert(string(T.ValueStatus) == "unavailable_runtime_execution_failed" && ...
    string(T.FailureReason) == "test:injected_channel_error", ...
    "The unavailable measurement and original error must remain explicit.");
ok = true;
end
