function ok = test5MHzSRSMeasuredPowerScheduling()
% Actual SRS waveform -> normal runtime ILLA consumer, not a full scenario.
setup6GRSimToolkit('Verbose',false);
scfg = sixgr.lls6g.config.loadScenarioConfig(fullfile('simulator','configs', ...
    'scenarios','lls_tdd_5mhz_rank2_shared_awgn_20db.yaml'));
cfg = sixgr.lls6g.buildInternalConfig(scfg,tempname);
slot = 30;
out = sixgr.link.runSRSChannelEstimation(cfg,'SNR_dB',20,'SlotIndex',slot);
assert(out.Ok && string(out.PredictedPUSCHPostEqSINRValueStatus)=="PASS", ...
    'Actual 5 MHz SRS must produce an independently measured PUSCH prediction.');
assert(out.PredictedPUSCHPostEqSINRCalibrationOffset_dB==0 && ...
    out.PUSCHToSRSReferenceEnergyRatio==1 && ...
    out.PredictedPUSCHReferenceSignalPower>0 && out.PredictedPUSCHDisturbancePower>0, ...
    'The waveform prediction must preserve native rank power, without a post-MMSE shift.');
out.ServingCell = 1;
state = localState(cfg);
state = sixgr.truth.CoupledTruthRuntime.updateLatestULFeedbackFromSRSTrialRuntime( ...
    state,1,out,slot);
fb = state.LatestULFeedback(1);
assert(fb.Valid && isfinite(fb.MCSIndex) && fb.InnerLoopEnabled && fb.OuterLoopEnabled, ...
    'Measured SRS must reach the real UL ILLA/OLLA state.');
assert(fb.RI==out.EstimatedRI && fb.RI<=2 && fb.PMI==out.EstimatedTPMI && ...
    fb.SourceSlot==slot && fb.DeliveredSlot==slot, ...
    'Runtime spatial selection and timing must preserve the received SRS decision.');
assert(state.ULLinkAdaptationState{1}.LastCQIFeedbackAbsoluteSlot==slot, ...
    'SRS-driven ILLA must retain the receiver-completion slot as its causal feedback clock.');
assert(abs(fb.SchedulerAdjustedSINR_dB + fb.SchedulerSINRBackoff_dB - ...
    out.PredictedPUSCHMinimumLayerSINR_dB)<1e-10, ...
    'UL ILLA must consume the weakest predicted layer, not the SRS pilot average.');

% A preserved data-quality decision must retain its own adaptation metadata.
% This old PUSCH is fresh at slot 30, and newer SRS is not a downgrade.
protected=state;
prior=fb; prior.FeedbackSourceSignal='PUSCH'; prior.FeedbackCRCPass=1;
prior.SourceSlot=29; prior.Slot=29; prior.DeliveredSlot=29;
prior.MCSIndex=0; prior.CQI=1; prior.SmoothedCQI=1.25;
prior.CQIBasedMCS=0.5; prior.InstantaneousCQIMCS=0;
prior.RI=1; prior.PMI=NaN;
protected.LatestULFeedback(1)=prior;
preserved=sixgr.truth.CoupledTruthRuntime.updateLatestULFeedbackFromSRSTrialRuntime( ...
    protected,1,out,slot);
kept=preserved.LatestULFeedback(1);
assert(kept.SourceSlot==29 && kept.MCSIndex==0 && kept.SmoothedCQI==1.25 && ...
    kept.CQIBasedMCS==0.5 && kept.InstantaneousCQIMCS==0, ...
    'sixgr:test:MixedFeedbackProvenance', ...
    'Preserving old PUSCH MCS must not attach a new SRS adaptation decision.');
assert(kept.RI==out.EstimatedRI && kept.PMI==out.EstimatedTPMI, ...
    'Independently received spatial feedback must still update.');
assert(preserved.ULLinkAdaptationState{1}.CQIObservationCount== ...
    protected.ULLinkAdaptationState{1}.CQIObservationCount+1 && ...
    preserved.ULLinkAdaptationState{1}.OLLAUpdateCount== ...
    protected.ULLinkAdaptationState{1}.OLLAUpdateCount);
% PUSCH preference must not outlive the scheduler's configured age limit.
expired=protected; expired.CfgMobility.phy.linkAdaptation.ulMaxCSIAgeSlots=5;
expired.LatestULFeedback(1).SourceSlot=24; expired.LatestULFeedback(1).Slot=24;
replaced=sixgr.truth.CoupledTruthRuntime.updateLatestULFeedbackFromSRSTrialRuntime( ...
    expired,1,out,slot);
assert(replaced.LatestULFeedback(1).SourceSlot==slot && ...
    string(replaced.LatestULFeedback(1).FeedbackSourceSignal)=="SRS", ...
    'Expired PUSCH feedback must not suppress newer eligible SRS.');
% Not-yet-delivered data feedback cannot suppress a completed SRS report.
pending=localState(cfg);
pending.PendingCSITable=table("UL",1,29,31,28,1,false, ...
    'VariableNames',{'Direction','UEIndex','SourceSlot','DueSlot','MCSIndex','CRCPass','Processed'});
received=sixgr.truth.CoupledTruthRuntime.updateLatestULFeedbackFromSRSTrialRuntime( ...
    pending,1,out,slot);
assert(received.LatestULFeedback(1).Valid && received.LatestULFeedback(1).SourceSlot==slot, ...
    'Pending undelivered report values are not scheduler knowledge.');

% Losing an exported provenance field must not silently install pilot CQI.
fields = ["PredictedPUSCHReferenceSignalPower","PredictedPUSCHDisturbancePower", ...
    "PUSCHToSRSReferenceEnergyRatio","PUSCHToSRSReferenceEnergySource", ...
    "PredictedPUSCHPostEqSINRSource"];
for name = fields
    missing = rmfield(out,char(name));
    rejected = sixgr.truth.CoupledTruthRuntime.updateLatestULFeedbackFromSRSTrialRuntime( ...
        localState(cfg),1,missing,slot);
    assert(~rejected.LatestULFeedback(1).Valid && ...
        ~isfinite(rejected.LatestULFeedback(1).MCSIndex), ...
        'Missing %s must not authorize a new PUSCH MCS.',name);
end
fprintf(['FIVE_MHZ_SRS_MEASURED_POWER_SCHEDULING_PASS RI=%g TPMI=%g ' ...
    'pilotSINR=%g predictedMinimumSINR=%g schedulerSINR=%g CQI=%g MCS=%g guards=%d\n'], ...
    fb.RI,fb.PMI,out.SINR_dB,out.PredictedPUSCHMinimumLayerSINR_dB, ...
    fb.SchedulerAdjustedSINR_dB,fb.CQI,fb.MCSIndex,numel(fields));
ok = true;
end

function state = localState(cfg)
latest = sixgr.truth.CoupledTruthRuntime.emptyLatestFeedbackRowRuntime();
state = struct('CfgMobility',cfg,'NumUsers',1,'DLSchedulers',{{}}, ...
    'ULSchedulers',{{sixgr.l2.mac.SchedulerRR(cfg,'Direction','UL')}}, ...
    'DLLinkAdaptationState',{{struct()}},'ULLinkAdaptationState',{{struct()}}, ...
    'LatestDLFeedback',latest,'LatestULFeedback',latest, ...
    'PendingCSITable',table(),'SlotDuration_s',1e-3);
end
