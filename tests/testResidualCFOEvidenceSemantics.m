function ok=testResidualCFOEvidenceSemantics()
% A circular zero must never hide a nonzero known diagnostic CFO error.
same=sixgr.phy.sync.resolveSynchronizationState( ...
    'InjectedCFO_Hz',430,'EstimatedCFO_Hz',500,'AppliedCFOCorrection_Hz',500, ...
    'ResidualCFOEstimate_Hz',0,'ResidualCFOReusesAcquisitionObservation',true);
assert(same.ResidualCFO_PostCorrection_Hz==-70 && ...
    same.ResidualCFOEstimatorConsistency_Hz==0 && ...
    same.ResidualCFOEstimateRole=="same_observation_estimator_consistency_not_independent_residual");
unknown=sixgr.phy.sync.resolveSynchronizationState('ResidualCFOEstimate_Hz',0);
assert(unknown.ResidualCFOEstimateRole=="post_correction_estimate_independence_not_established" && ...
    isnan(unknown.ResidualCFO_PostCorrection_Hz) && isnan(unknown.ResidualCFOEstimatorConsistency_Hz));
missing=sixgr.phy.sync.resolveSynchronizationState();
assert(missing.ResidualCFOEstimateRole=="unavailable" && ...
    isnan(missing.ResidualCFO_EstimatedPostCorrection_Hz));
T=sixgr.link.addCFOObservationColumns(table((1:3)','VariableNames',{'Trial'}), ...
    {struct();struct();struct()},{same;unknown;struct()});
assert(T.ResidualCFOReusesAcquisitionObservation(1)==1 && ...
    T.ResidualCFOEstimatorConsistency_Hz(1)==0 && ...
    isnan(T.ResidualCFOEstimatorConsistency_Hz(2)) && ...
    isnan(T.ResidualCFOReusesAcquisitionObservation(3)) && ...
    T.ResidualCFOEstimateRole(3)=="not_reported_by_receiver");
empty=sixgr.link.addCFOObservationColumns(table(),cell(0,1),cell(0,1));
assert(height(empty)==0 && ismember('ResidualCFOEstimateRole',empty.Properties.VariableNames));
assert(testDataReceiverSynchronizationAuthority());
fprintf('RESIDUAL_CFO_EVIDENCE_PASS same_capture_zero_not_independent; DL_UL_producers_verified\n');
ok=true;
end
