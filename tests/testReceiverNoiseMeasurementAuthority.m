function ok=testReceiverNoiseMeasurementAuthority()
% Receiver-measured noise must not be supplied, oracle or model noise.
setup6GRSimToolkit('Verbose',false,'RunToolboxChecks',false);
measuredInfo=struct('Method','LS','EstimatorUsesTrueChannel',false);
for estimate=[0 .02 2e6]
    [value,source]=sixgr.phy.rx.receiverNoiseMeasurement( ...
        estimate,measuredInfo,"independent_test_dmrs_estimator");
    assert(value==estimate && source=="independent_test_dmrs_estimator");
end
for invalid={[],NaN,Inf,-1,[1 2],1+1i,'0.02'}
    [value,source]=sixgr.phy.rx.receiverNoiseMeasurement( ...
        invalid{1},measuredInfo,"independent_test_dmrs_estimator");
    assert(isnan(value) && source=="unavailable_invalid_independent_dmrs_noise_estimate");
end
blocked={struct('EstimatorUsesTrueChannel',true), ...
    struct('OracleTestMode',true),struct('FullCovarianceLMMSE',true), ...
    struct('Method','LMMSE')};
for index=1:numel(blocked)
    [value,source]=sixgr.phy.rx.receiverNoiseMeasurement( ...
        .02,blocked{index},"independent_test_dmrs_estimator");
    assert(isnan(value) && contains(source,"not_receiver_measurement"));
end
[value,source]=sixgr.phy.rx.receiverNoiseMeasurement(.02,measuredInfo, ...
    "independent_test_dmrs_estimator",'UnitAWGNShortcut',true);
assert(isnan(value) && source== ...
    "unavailable_unit_awgn_configured_noise_not_receiver_measurement");
rx=struct('MeasuredPreEqualizationNoiseVariance',.02, ...
    'MeasuredPreEqualizationNoiseVarianceSource',"independent_test_dmrs_estimator", ...
    'PreEqualizationNoiseVariance',.3);
exported=sixgr.link.deriveMeasuredPHYEvidence(rx);
assert(exported.MeasuredPreEqualizationNoiseVariance==.02 && ...
    exported.MeasuredPreEqualizationNoiseVarianceSource== ...
    "independent_test_dmrs_estimator", ...
    'The compact export must retain the measured value and its own source.');
T=sixgr.link.appendMeasuredPHYEvidenceColumns(table(1,'VariableNames',{'Trial'}),{exported});
assert(T.MeasuredPreEqualizationNoiseVariance==.02 && ...
    T.MeasuredPreEqualizationNoiseVarianceSource=="independent_test_dmrs_estimator");
emptyT=sixgr.link.appendMeasuredPHYEvidenceColumns(table(),{});
assert(height(emptyT)==0 && ...
    ismember('MeasuredPreEqualizationNoiseVarianceSource',emptyT.Properties.VariableNames));
missing=sixgr.link.deriveMeasuredPHYEvidence(struct('PreEqualizationNoiseVariance',.3));
assert(isnan(missing.MeasuredPreEqualizationNoiseVariance) && ...
    strlength(missing.MeasuredPreEqualizationNoiseVarianceSource)==0, ...
    'Missing measured noise must not be reconstructed from equalizer metadata.');
ok=true;
end
