function ok = testStrictnessMetadataConsistency()
%TESTSTRICTNESSMETADATACONSISTENCY Keep E2E summary and manifest strictness metadata aligned.

setup6GRSimToolkit("Verbose", false);

root = fullfile(pwd,'results','sls','strictness_metadata', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
tmpTruth = fullfile(root,'campaign_nonstrict_e2e_strict');
mkdir(tmpTruth);
fprintf('STRICTNESS_METADATA_EVIDENCE_ROOT=%s\n',root);
[cfg,nSlots] = e2eReceivedAccessConfig(tmpTruth,2,"mmtc");
cfg.run.shortRun = true;
cfg.run.strictMode = false;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.run.seed = 41;

save(fullfile(tmpTruth,'test_configuration.mat'),'cfg','nSlots');

repTruth = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmpTruth, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", nSlots*sixgr.time.slotDurationSec(cfg), ...
    "E2EMaxSlots", nSlots, ...
    "E2EUECount", 2, ...
    "E2ETrafficModel", "mmtc", ...
    "E2EAirModel", "truth", ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", false, ...
    "GenerateCampaignPlots", false, ...
    "E2EStrictValidation", true, ...
    "E2ETruthFastAWGNPath", false, ...
    "E2ETruthMaxSlots", nSlots);
save(fullfile(tmpTruth,'test_output.mat'),'repTruth','-v7.3');
localAssertExecutedBidirectional(repTruth);

runTruth = char(string(repTruth.RunFolder));
layoutTruth = sixgr.report.resultLayout(runTruth);
sumTruth = readtable(fullfile(layoutTruth.PacketFlowCSVDir, "probe_e2e_summary_truth.csv"), "VariableNamingRule", "preserve");
manTruth = jsondecode(fileread(layoutTruth.RunManifestJSON));
assert(~logical(manTruth.CampaignStrictMode) && logical(manTruth.E2EStrictValidation), ...
    'Preserve the campaign-nonstrict/E2E-strict test branch.');

assert(logical(sumTruth.StrictValidationMode(1)) == logical(manTruth.E2EStrictValidation), ...
    "Truth summary strictness must match manifest E2E strict validation.");
assert(logical(sumTruth.E2EStrictValidation(1)) == logical(manTruth.E2EStrictValidation), ...
    "Truth summary explicit E2E strictness must match manifest.");
assert(logical(sumTruth.CampaignStrictMode(1)) == logical(manTruth.CampaignStrictMode), ...
    "Truth summary campaign strict mode must match manifest.");
assert(logical(sumTruth.OnlyE2E(1)) == logical(manTruth.OnlyE2E), ...
    "Truth summary OnlyE2E flag must match manifest.");
assert(logical(sumTruth.LinkStrictValidation(1)) == logical(manTruth.LinkStrictValidation), ...
    "Truth summary link strictness must match manifest.");
assert(logical(sumTruth.SystemStrictValidation(1)) == logical(manTruth.SystemStrictValidation), ...
    "Truth summary system strictness must match manifest.");
assert(~isfield(manTruth, "CalibrationSource") || strlength(string(manTruth.CalibrationSource)) == 0, ...
    "Truth-only run should not claim calibration provenance.");

tmpCal = fullfile(root,'campaign_strict_e2e_nonstrict');
mkdir(tmpCal);
[cfgCal,nSlotsCal] = e2eReceivedAccessConfig(tmpCal,2,"xr");
cfgCal.run.shortRun = true;
cfgCal.run.seed = 41;
cfgCal.outputs = cfg.outputs;
cfgCal.run.strictMode = true;
save(fullfile(tmpCal,'test_configuration.mat'),'cfgCal','nSlotsCal');

repCal = sixgr_run_3gpp_full_campaign(cfgCal, ...
    "ResultsRoot", tmpCal, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", nSlotsCal*sixgr.time.slotDurationSec(cfgCal), ...
    "E2EMaxSlots", nSlotsCal, ...
    "E2ETruthMaxSlots", nSlotsCal, ...
    "E2EUECount", 2, ...
    "E2ETrafficModel", "xr", ...
    "E2EAirModel", "truth", ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", false, ...
    "GenerateCampaignPlots", false, ...
    "E2EStrictValidation", false);
save(fullfile(tmpCal,'test_output.mat'),'repCal','-v7.3');
localAssertExecutedBidirectional(repCal);

runCal = char(string(repCal.RunFolder));
layoutCal = sixgr.report.resultLayout(runCal);
sumCal = readtable(fullfile(layoutCal.PacketFlowCSVDir, "probe_e2e_summary_truth.csv"), "VariableNamingRule", "preserve");
manCal = jsondecode(fileread(layoutCal.RunManifestJSON));
assert(logical(manCal.CampaignStrictMode) && ~logical(manCal.E2EStrictValidation), ...
    'Preserve the campaign-strict/E2E-nonstrict test branch.');

assert(logical(sumCal.StrictValidationMode(1)) == logical(manCal.E2EStrictValidation), ...
    "Calibration-export run summary strictness must match manifest E2E strict validation.");
assert(~isfield(manCal, "CalibrationSourceKind") || strlength(string(manCal.CalibrationSourceKind)) == 0, ...
    "Truth-only run must not export calibration provenance fields.");
assert(~isfield(manCal, "CalibrationUsedByThisRun") || ~logical(manCal.CalibrationUsedByThisRun), ...
    "Truth-only run must not claim calibration usage.");

ok = true;
end

function localAssertExecutedBidirectional(rep)
assert(height(rep.E2E.ReceivedAccessBindings)==2, ...
    'Strictness metadata must accompany actual access for both UEs.');
G=rep.E2E.SchedulerTraceTable;
assert(~isempty(G) && all(ismember(["DL","UL"],upper(string(G.Direction)))), ...
    'Strictness metadata coverage requires executed DL and UL grants.');
end
