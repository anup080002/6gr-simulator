function ok = testControlDataAllocationIndependence()
%TESTCONTROLDATAALLOCATIONINDEPENDENCE Exact control/data RE independence.

setup6GRSimToolkit("Verbose", false);
localToolboxRateMatchProof();
localStrictTDRAAndMappingBTransmission();
localCORESETNoClampValidation();
ok = true;
end

function localToolboxRateMatchProof()
[carrier, pdcch] = localPDCCHObjects();
pdcchSnapshot = localPDCCHSnapshot(pdcch);
pdcchAllocation = sixgr.phy.frame. ...
    ChannelAllocationMaterializer.materializePDCCH( ...
    carrier, pdcch, "GridID", "cc0_bwp0_grid", ...
    "TestID", "PDCCH_CANDIDATE");

assert(pdcchAllocation.Exact && ~pdcchAllocation.FallbackUsed && ...
    pdcchAllocation.Data.RECount > 0 && ...
    pdcchAllocation.DMRS.RECount > 0, ...
    "PDCCH allocation must be generated by nrPDCCHResources.");
assert(pdcchAllocation.CORESETMonitoringOccasion.StartSymbol == 0 && ...
    pdcchAllocation.CORESETMonitoringOccasion.NumSymbols == 2, ...
    "The two-symbol CORESET monitoring occasion was not preserved.");
assert(localPDCCHSnapshot(pdcch) == pdcchSnapshot, ...
    "PDCCH materialization mutated the input Toolbox object.");

pdsch = nrPDSCHConfig;
pdsch.PRBSet = 0:23;
pdsch.SymbolAllocation = [0 14];
pdsch.MappingType = "A";
pdsch.Modulation = "QPSK";
pdcchIndices = unique([pdcchAllocation.Data.Indices1Based; ...
    pdcchAllocation.DMRS.Indices1Based], "stable");
pdsch.ReservedRE = pdcchIndices - 1;
pdschSnapshot = localPDSCHSnapshot(pdsch);
pdschAllocation = sixgr.phy.frame. ...
    ChannelAllocationMaterializer.materializePDSCH( ...
    carrier, pdsch, "GridID", "cc0_bwp0_grid", ...
    "TestID", "PDSCH_FULL_SLOT");

assert(pdschAllocation.RateMatchProof.Exact && ...
    pdschAllocation.RateMatchProof.NoOccupiedReservedRECollision && ...
    pdschAllocation.RateMatchProof.ToolboxDataExcludesReservedRE && ...
    pdschAllocation.RateMatchProof.ToolboxDMRSExcludesReservedRE && ...
    isequal(sort(pdschAllocation.Reserved.Indices1Based), ...
        sort(pdcchIndices)), ...
    "PDSCH rate matching must be proven by exact nrPDCCHResources and nrPDSCHIndices.");
assert(localPDSCHSnapshot(pdsch) == pdschSnapshot, ...
    "PDSCH materialization mutated the input Toolbox object.");

state = localFixedState('D');
legal = sixgr.phy.frame.ResourceAllocationValidator.validateSet( ...
    [pdcchAllocation.CandidateAllocation ...
     pdschAllocation.Allocation], state);
assert(legal.ActualValid && ...
    legal.ReasonCode == "no_unhandled_re_collision", ...
    "Toolbox-backed PDCCH/PDSCH rate matching must be legal.");
assert(legal.Results(2).Allocation.StartSymbol == 0 && ...
    legal.Results(2).Allocation.NumSymbols == 14 && ...
    legal.Results(2).ReasonCode == ...
        "preserve_explicit_full_slot_pdsch_no_auto_shift", ...
    "PDSCH symbols 0-13 must not be shifted after the CORESET.");
assert(isequal(sort(legal.Results(2).Occupancy.REKey), ...
    sort(pdschAllocation.ActualREKeys)), ...
    "Validated PDSCH occupancy must equal the exact Toolbox data/DMRS/PTRS set.");

unproven = pdschAllocation.Allocation;
unproven.ReservedREKeys = strings(0, 1);
localAssertError(@() ...
    sixgr.phy.frame.ResourceAllocationValidator.validateSet( ...
    [pdcchAllocation.CandidateAllocation unproven], state), ...
    "sixgr:phy:frame:UnprovenRateMatchReservation");

pdschWithoutReservation = nrPDSCHConfig;
pdschWithoutReservation.PRBSet = pdsch.PRBSet;
pdschWithoutReservation.SymbolAllocation = pdsch.SymbolAllocation;
pdschWithoutReservation.MappingType = pdsch.MappingType;
pdschWithoutReservation.Modulation = pdsch.Modulation;
illegalAllocation = sixgr.phy.frame. ...
    ChannelAllocationMaterializer.materializePDSCH( ...
    carrier, pdschWithoutReservation, "GridID", "cc0_bwp0_grid", ...
    "TestID", "PDSCH_UNRESERVED");
illegal = sixgr.phy.frame.ResourceAllocationValidator.validateSet( ...
    [pdcchAllocation.CandidateAllocation ...
     illegalAllocation.Allocation], state);
assert(~illegal.ActualValid && ...
    illegal.ReasonCode == "unreserved_re_collision" && ...
    ~isempty(illegal.CollisionKeys), ...
    "An actual unreserved Toolbox RE collision must fail.");
end

function localStrictTDRAAndMappingBTransmission()
carrier = nrCarrierConfig;
carrier.NSizeGrid = 24;
carrier.SubcarrierSpacing = 30;
carrier.NCellID = 7;

missing = localPDSCHCfg();
missing.run.strictMode = true;
missing.phy.pdsch = rmfield(missing.phy.pdsch, ...
    ["symbolAllocation","mappingType"]);
localAssertError(@() sixgr.phy.dl.PDSCH_Tx( ...
    missing, "Carrier", carrier, "CompactOutput", true), ...
    "sixgr:phy:grid:allocREsPDSCH:MissingExplicitTDRA");

cfg = localPDSCHCfg();
cfg.run.strictMode = true;
cfg.phy.pdsch.symbolAllocation = [2 10];
cfg.phy.pdsch.mappingType = "B";
[tx, ~] = sixgr.phy.dl.PDSCH_Tx( ...
    cfg, "Carrier", carrier, "CompactOutput", true);
assert(string(tx.PDSCH.MappingType) == "B" && ...
    isequal(double(tx.PDSCH.SymbolAllocation), [2 10]), ...
    "Strict PDSCH Tx must preserve an explicit mapping-B TDRA.");
end

function localCORESETNoClampValidation()
ctrl = struct("NSizeGrid", 24, "CellID", 7, ...
    "SubcarrierSpacing_kHz", 30, "SymbolsPerSlot", 14);
valid = sixgr.ctrl.CORESETConfig(struct( ...
    "DurationSymbols", 2, "StartSymbol", 1, ...
    "NumRB", 12, "RBStart", 6), ctrl);
assert(valid.DurationSymbols == 2 && valid.StartSymbol == 1 && ...
    valid.NumRB == 12 && valid.RBStart == 6, ...
    "Valid CORESET inputs must be preserved exactly.");

localAssertError(@() sixgr.ctrl.CORESETConfig( ...
    struct("DurationSymbols", 0), ctrl), ...
    "sixgr:ctrl:CORESETConfig:BadDuration");
localAssertError(@() sixgr.ctrl.CORESETConfig( ...
    struct("DurationSymbols", 4), ctrl), ...
    "sixgr:ctrl:CORESETConfig:BadDuration");
localAssertError(@() sixgr.ctrl.CORESETConfig( ...
    struct("StartSymbol", -1), ctrl), ...
    "sixgr:ctrl:CORESETConfig:BadSymbolWindow");
localAssertError(@() sixgr.ctrl.CORESETConfig( ...
    struct("NumRB", 0), ctrl), ...
    "sixgr:ctrl:CORESETConfig:BadFrequencyAllocation");
localAssertError(@() sixgr.ctrl.CORESETConfig( ...
    struct("RBStart", -1), ctrl), ...
    "sixgr:ctrl:CORESETConfig:BadFrequencyAllocation");
localAssertError(@() sixgr.ctrl.CORESETConfig( ...
    struct("FrequencyAllocationMode", "noncontiguous", ...
    "RBSetList", [0 1.5 2]), ctrl), ...
    "sixgr:ctrl:CORESETConfig:BadFrequencyAllocation");
localAssertError(@() sixgr.ctrl.CORESETConfig( ...
    struct("NumRB", 12, "RBStart", 18), ctrl), ...
    "sixgr:ctrl:CORESETConfig:RBOutOfRange");
end

