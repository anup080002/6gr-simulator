function value = localPDCCHSnapshot(pdcch)
value = string(jsonencode(struct( ...
    "Duration", double(pdcch.CORESET.Duration), ...
    "FrequencyResources", double(pdcch.CORESET.FrequencyResources), ...
    "StartSymbol", double(pdcch.SearchSpace.StartSymbolWithinSlot), ...
    "AggregationLevel", double(pdcch.AggregationLevel), ...
    "AllocatedCandidate", double(pdcch.AllocatedCandidate))));
end

function value = localPDSCHSnapshot(pdsch)
value = string(jsonencode(struct( ...
    "PRBSet", double(pdsch.PRBSet), ...
    "SymbolAllocation", double(pdsch.SymbolAllocation), ...
    "MappingType", string(pdsch.MappingType), ...
    "ReservedRE", double(pdsch.ReservedRE))));
end

function state = localFixedState(direction)
state = struct("DuplexMode", "TDD", ...
    "CommonDirection", repmat(direction, 1, 14), ...
    "DedicatedDirection", strings(1, 14), ...
    "SymbolDirection", repmat(direction, 1, 14), ...
    "ResolvedDirection", repmat(string(direction), 1, 14), ...
    "ResolutionSource", strings(1, 14), ...
    "AllocationOwner", strings(1, 14));
end

function localAssertError(fcn, expectedID)
threw = false;
try
    fcn();
catch cause
    threw = true;
    assert(string(cause.identifier) == string(expectedID), ...
        "Expected error %s, got %s: %s", ...
        expectedID, cause.identifier, cause.message);
end
assert(threw, "Expected error %s was not thrown.", expectedID);
end
