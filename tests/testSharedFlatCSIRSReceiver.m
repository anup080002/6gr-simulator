function ok=testSharedFlatCSIRSReceiver(snr,withCSIIM)
% Real PDSCH/CSI-RS waveform, shared 4x2 channel/noise/RF and PDSCH_Rx.
% Explicit calibration assignment, not PDCCH/access or scenario acceptance.
setup6GRSimToolkit('Verbose',false);
if nargin<1, snr=20; end
if nargin<2, withCSIIM=false; end
validateattributes(snr,{'numeric'},{'real','finite','scalar'});
s=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_tdd_5mhz_rank2_4tx2rx_awgn_m10db.yaml');
sc=s.toStruct(); sc.reference_signals.csi_rs_runtime_channel_estimator='flat_static_awgn_ls';
if withCSIIM
    % Explicit calibration resource outside this occasion's SSB/DM-RS.
    % The production allocator must mute it; the test never zeros TX REs.
    sc.reference_signals.csi_im=struct('enabled',true,'resource_id',0,'pattern',1, ...
        'subcarrier',4,'symbol',13,'starting_rb',0,'num_rbs',24, ...
        'period_slots',5,'offset_slots',1);
end
sixgr.lls6g.config.validateScenarioConfig(sc);
cfg=sixgr.lls6g.buildInternalConfig(sc,tempname);
assert(string(cfg.phy.csirs.runtimeChannelEstimator)=="flat_static_awgn_ls");
cfg=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,2);
cfg.channel.snr_dB=snr;
% This CSI occasion also carries SSB. Use a legal two-symbol allocation
% after its burst, rather than bypassing the production SSB/DM-RS guard.
cfg.phy.pdsch.SymbolAllocation=[12 2]; cfg.phy.pdsch.symbolAllocation=[12 2];
cfg.phy.pdsch.MappingType='B'; cfg.phy.pdsch.mappingType='B';
cfg.phy.pdsch.dmrs.additionalPosition=0;
cfg=sixgr.util.structSet(cfg,'lls6g.runtimePowerContext.WaveformAmplitudeUnit','sqrt_mW');
precoder=ones(4,1)/2; % Explicit unit-norm rank-one calibration assignment.
cfg.phy.pdsch.selectedPrecoderSHA256=sixgr.phy.mimo.MatrixContract.digest(precoder);
[tx,txInfo]=sixgr.phy.dl.PDSCH_Tx(cfg,'ExecutionProfile','phy_calibration', ...
    'PrecodingMatrix',precoder,'CompactOutput',false);
assert(size(tx.Waveform,2)==4 && ~isempty(tx.CSIRSIndices));
if withCSIIM
    assert(tx.CSIIMResource.Scheduled && tx.CSIIMResource.NumRE==96);
    txGrid=nrOFDMDemodulate(tx.Carrier,tx.Waveform);
    plane=reshape(txGrid,[],size(txGrid,3));
    assert(max(abs(plane(tx.CSIIMResource.PhysicalIndices1Based,:)),[],'all')<1e-10, ...
        'Serving PDSCH/SSB/CSI waveform contaminated configured CSI-IM REs.');
end
fs=txInfo.OFDM.SampleRate; count=size(tx.Waveform,1);
state=sixgr.channel.ChannelFactory.createRuntimeChannelState(cfg,'DL','UEIndex',1,'ServingCell',1);
state.TargetUEIndex=1; state.TargetServingCell=1;
state=sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    state,cfg,zeros(1,4),txInfo,'NumTxAnt',4,'NumRxAnt',2);
owner=sixgr.truth.SharedWaveformPhysicalRuntime(fs,0,1);
owner.addTransmitter('gnb',cfg,'DL',4,false);
owner.addReceiver('ue',cfg,'DL',2,false);
owner.addLink('matrix','gnb','ue',state,cfg);
event=sixgr.phy.waveform.WaveformEventRuntime(fs,0,@owner.process,owner);
owner.attach(event,'double');
event.enqueue('gnb','pdsch_csirs',sixgr.phy.waveform.WaveformChunk(tx.Waveform,0));
event.commitTransmissionsThrough('gnb',count);
for plane=["gnb:tx","ue:pre_rf","ue:post_rf"]
    event.observe(plane,'csi_receiver_component',0,count);
end
done=event.advanceUntilEvent(count);
[~,pre,~,replay,received]=sixgr.truth.sharedObservationEvidence(done.Completed);
sixgr.phy.rx.assertFlatStaticAWGNObservation(replay);
assert(replay.AppliedAWGNSNR_dB==snr);
rx=sixgr.phy.dl.PDSCH_Rx(received.readComplete(),cfg, ...
    'ExecutionProfile','phy_calibration','Carrier',tx.Carrier,'PDSCH',tx.PDSCH, ...
    'PrecodingMatrix',precoder, ...
    'PDSCHIndices',tx.PDSCHIndices,'CodingPlan',tx.CodingPlans, ...
    'CodingLayout',tx.CodingLayout,'TransportBlockSize',tx.TransportBlockSize, ...
    'TargetCodeRate',tx.TargetCodeRate,'RV',tx.RV, ...
    'PhysicalMeasurementWaveform',pre.readComplete(), ...
    'PhysicalMeasurementSource','actual_shared_pre_rf_component_capture', ...
    'PhysicalMeasurementReferencePlane','receiver_antenna_connector_pre_composite_front_end', ...
    'ReceivedExecutionEvidence',replay);
assert(rx.CSIRSChannelEstimation.Available && ...
    string(rx.CSIRSChannelEstimation.ChannelEstimator)=="received_known_pilot_flat_static_joint_least_squares");
assert(size(rx.CSIRSChannelEstimate,3)==2 && size(rx.CSIRSChannelEstimate,4)==4);
assert(~isempty(fieldnames(rx.CSIRSChannelEstimation.ReferencePowerMeasurement)));
assert(isfinite(rx.CSIRSObservation.PilotResidualPower) && ...
    rx.CSIRSObservation.PilotResidualPower>=0 && ...
    isfinite(rx.CSIRSObservation.PilotResidualNMSE_dB), ...
    'The received CSI-RS observation must retain finite pilot-residual diagnostics.');
fprintf('SHARED_CSI_MEASUREMENT status=%s blocker=%s errors=%s source=%s\n', ...
    string(rx.CSIRSObservation.PhysicalMeasurementStatus),string(rx.CSIRSObservation.Blocker), ...
    string(rx.CSIRSObservation.MeasurementErrors),string(rx.CSIRSObservation.RuntimeMaterializationStatus));
assert(strlength(rx.CSIRSObservation.ReferenceSINRMeasurementJSON)>0);
% Compare the independently callable CSI receiver with the existing facade
% on these same actually captured grids, without a second data decode.
assert(~rx.CFOCorrectionApplied,'This comparison fixture declares CFO disabled.');
preSamples=pre.readComplete();
preGrid=nrOFDMDemodulate(tx.Carrier, ...
    preSamples(rx.AppliedTimingCorrection_samples+1:end,:));
gridInput=struct('OFDMGrid',rx.RxGrid,'OFDMInfo',nrOFDMInfo(tx.Carrier), ...
    'InterferenceCovariance',rx.InterferenceCovariance, ...
    'InterferenceCovarianceIncludesNoise',rx.InterferenceCovarianceIncludesNoise);
gridOptions=struct('PhysicalMeasurementGrid',preGrid, ...
    'PhysicalMeasurementOFDMInfo',nrOFDMInfo(tx.Carrier), ...
    'PhysicalMeasurementGridStatus',"available_exact_pre_front_end_grid", ...
    'PhysicalMeasurementReferencePlane',"receiver_antenna_connector_pre_composite_front_end", ...
    'PhysicalMeasurementSource',"actual_shared_pre_rf_component_capture", ...
    'ReceivedExecutionEvidence',replay);
independent=sixgr.phy.refsig.receiveCSIRSFromGrid(tx.Carrier,cfg,gridInput,gridOptions);
assert(isequaln(rx.CSIRSChannelEstimate,independent.CSIRSChannelEstimate) && ...
    rx.CSIRSNoiseVar==independent.CSIRSNoiseVar && ...
    rx.CSIMeasurementState.Digest==independent.CSIMeasurementState.Digest && ...
    rx.CSIRSObservation.ReferenceSINRMeasurementJSON== ...
    independent.CSIRSObservation.ReferenceSINRMeasurementJSON, ...
    'Extracting CSI reception must preserve the same receiver evidence exactly.');
fprintf('SHARED_CSI_INDEPENDENT_GRID_PARITY_PASS configured_snr=%g CSIIM=%d\n',snr,withCSIIM);
% The independent receiver must also preserve the measured beam/rank/CQI
% decision and the actual UCI bits. It has no PDSCH decoder or CRC fields.
% DM-RS here describes the installed reporting hypothesis, not an accepted
% data grant and not transmitted data/reference bits used as an RX oracle.
reports=cell(2,1);
measurement=rx.CSIMeasurementState;
reports{1}=sixgr.phy.dl.CSI_Feedback( ...
    measurement.ChannelEstimate,measurement.NoiseVariance,cfg, ...
    'Direction','DL','MeasurementState',measurement, ...
    'ReportConfiguration',cfg.phy.csi.reportConfiguration, ...
    'Carrier',tx.Carrier,'CSIRSConfig',rx.SelectedCSIRS, ...
    'PDSCHDMRSConfig',tx.PDSCH.DMRS, ...
    'FullChannelEstimate',rx.CSIRSChannelEstimate);
[reports{2},independentReportInfo]= ...
    sixgr.phy.refsig.computeCSIRSFeedback(tx.Carrier,cfg,independent);
assert(~independentReportInfo.PDSCHDecodeAttempted && ...
    ~independentReportInfo.DCIConsumed && ...
    ~independentReportInfo.HARQStateConsumed && ...
    independentReportInfo.MeasurementDigest==independent.CSIMeasurementState.Digest, ...
    'Independent CSI report generation must consume only its immutable received measurement.');
for field=["RI","PMI","CQI","CRI","Precoder_W","SINR_dB", ...
        "CSIPart1Bits","CSIPart2Bits"]
    assert(isequaln(reports{1}.(field),reports{2}.(field)), ...
        'Independent CSI reception changed measured report field %s.',field);
end
assert(~isfield(independent,'CRCError') && ~isfield(independent,'PDSCH'));
fprintf('SHARED_CSI_INDEPENDENT_REPORT_PARITY_PASS RI=%g PMI=%g CQI=%g bits=%g\n', ...
    reports{2}.RI,reports{2}.PMI,reports{2}.CQI, ...
    numel(reports{2}.CSIPart1Bits)+numel(reports{2}.CSIPart2Bits));
% Fixed-Es/N0 export deliberately clears absolute-dBm resource records.
% The dimensionless selected SINR and its estimator evidence stay in JSON.
measured=jsondecode(rx.CSIRSObservation.ReferenceSINRMeasurementJSON);
assert(measured.Available && ...
    string(measured.Source)=="received_flat_LS_noise_debiased_port3000_reference_RE_power");
if withCSIIM
    im=rx.CSIRSChannelEstimation.InterferenceMeasurement;
    assert(im.Available && im.IncludesNoise && im.SampleCount==96);
    assert(rx.CSIRSNoiseVar==im.MeanPower);
    assert(measured.InterferenceMeasurement.Available && ...
        string(measured.DisturbanceSource)=="configured_CSI_IM_received_RE_second_moment");
end
folder=fullfile(pwd,'results','lls','shared_flat_csirs_receiver',char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(folder);
row=table(replay.AppliedAWGNSNR_dB,rx.CRCError,rx.CSIRSNoiseVar,measured.CSI_SINR_dB, ...
    string(rx.CSIRSObservation.ReferenceSINRMeasurementJSON), ...
    'VariableNames',{'AppliedAWGNSNR_dB','PDSCHCRCError','CSIRSNoiseVariance','MeasuredCSISINR_dB','MeasurementJSON'});
row.CSIIMEnabled=logical(withCSIIM);
writetable(row,fullfile(folder,'receiver.csv'));
fprintf('SHARED_FLAT_CSIRS_RECEIVER_PASS dataCRC=%d SINR=%g output=%s\n',~rx.CRCError,measured.CSI_SINR_dB,folder);
ok=true;
end
