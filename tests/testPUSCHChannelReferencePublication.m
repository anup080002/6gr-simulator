function ok=testPUSCHChannelReferencePublication(folder)
% Actual decoder outputs must retain the estimator's effective-layer pilots.
% Native antenna-domain DMRS remains separately available for RE accounting.
setup6GRSimToolkit('Verbose',false);
if nargin<1, [~,folder]=testDataChannelEstimateScoring(); end
rows=struct([]); complete=true;
for layers=[1 2]
    for snr=[-10 20]
        saved=load(fullfile(folder,sprintf('UL_rank%d_snr%d.mat',layers,snr)));
        rx=saved.receiver;
        refs=sixgr.phy.ul.puschChannelEstimateReferences(rx);
        cfg=sixgr.config.defaultConfig();
        cfg.phy.nTxAnt=2; cfg.phy.nRxAnt=4;
        cfg.phy.pusch.nLayers=layers; cfg.phy.pusch.numLayers=layers;
        cfg.phy.csi.reportCQI=false;
        native=sixgr.phy.ul.measureULLinkState(rx.ChannelEstimate,rx.NoiseVar,cfg, ...
            'ReceivedGrid',rx.RxGrid,'ReferenceIndices',rx.DMRSIndices, ...
            'ReferenceSymbols',rx.DMRSSymbols, ...
            'ChannelEstimateDomain','pusch_dmrs_effective_layer_domain');
        effective=sixgr.phy.ul.measureULLinkState(rx.ChannelEstimate,rx.NoiseVar,cfg, ...
            'ReceivedGrid',rx.RxGrid,'ReferenceIndices',refs.Indices, ...
            'ReferenceSymbols',refs.Symbols, ...
            'ChannelEstimateDomain','pusch_dmrs_effective_layer_domain');
        assert(isfinite(effective.PilotSINR_dB) && string(effective.PilotSINRValueStatus)=="OK");
        published=all(isfield(rx,{'ChannelEstimateReferenceIndices', ...
            'ChannelEstimateReferenceSymbols','ChannelEstimateReferenceDomain'}));
        complete=complete && published;
        if published
            assert(isequal(rx.ChannelEstimateReferenceIndices,refs.Indices) && ...
                isequal(rx.ChannelEstimateReferenceSymbols,refs.Symbols) && ...
                string(rx.ChannelEstimateReferenceDomain)=="effective_layer_channel");
            assert(rx.MeasuredDMRSPortCount==layers && ...
                rx.MeasuredDMRSAntennaPortCount==2);
            assert(refs.Source=="actual_PUSCH_receiver_channel_estimator_inputs" && ...
                isfield(rx,'ReceiverOFDMInfo'));
            phase=sixgr.phy.rx.pilotChannelPhaseEvolution(rx.Carrier, ...
                rx.ChannelEstimate,refs.Indices,refs.Symbols,rx.ReceiverOFDMInfo);
            pilotSymbols=unique(mod(floor((double(refs.Indices(:))-1)/ ...
                (12*rx.Carrier.NSizeGrid)),rx.Carrier.SymbolsPerSlot));
            if numel(pilotSymbols)==1
                % This default DM-RS fixture has no temporal baseline.
                % Publishing zero phase rate would invent a measurement.
                assert(phase.PairCount==0 && isnan(phase.CommonPhaseRate_Hz) && ...
                    phase.Status=="insufficient_repeated_pilot_coordinates");
            else
                assert(phase.PairCount>0 && isfinite(phase.CommonPhaseRate_Hz));
            end
            % Do not silently regenerate a conflicting captured reference.
            bad=rx; bad.ChannelEstimateReferenceSymbols(1)= ...
                bad.ChannelEstimateReferenceSymbols(1)*1i;
            caught=false;
            try, sixgr.phy.ul.puschChannelEstimateReferences(bad);
            catch ex, caught=strcmp(ex.identifier,'sixgr:phy:ul:PUSCHCapturedReferenceMismatch'); end
            assert(caught,'Corrupted estimator-reference provenance must remain observable.');
        end
        entry=struct('Layers',layers,'ConfiguredSNR_dB',snr, ...
            'NativePilotStatus',string(native.PilotSINRValueStatus), ...
            'NativePilotSINR_dB',native.PilotSINR_dB, ...
            'EffectivePilotStatus',string(effective.PilotSINRValueStatus), ...
            'EffectivePilotSINR_dB',effective.PilotSINR_dB, ...
            'EstimatorReferencesPublished',published,'DecodeCRCOK',rx.CRCPass, ...
            'Source',"actual_PUSCH_receiver_postdecode_reference_domain_audit");
        if isempty(rows), rows=entry; else, rows(end+1)=entry; end %#ok<AGROW>
        fprintf('PUSCH_REFERENCE_PUBLICATION rank=%d snr=%g native=%s effective=%s published=%d\n', ...
            layers,snr,entry.NativePilotStatus,entry.EffectivePilotStatus,published);
    end
end
writetable(struct2table(rows),fullfile(folder,'pusch_reference_publication.csv'));
assert(complete,'test:PUSCHEstimatorReferencePublicationMissing', ...
    'Actual PUSCH_Rx output must publish its own estimator references, not only native physical-port pilots.');
fprintf('PUSCH_REFERENCE_PUBLICATION_PASS cases=%d output=%s\n',numel(rows),folder);
ok=true;
end
