function ok = testLLSComponentArtifactViews()
%TESTLLSCOMPONENTARTIFACTVIEWS Legacy mirrors remain testable but retired.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
root = string(tempname);
mkdir(fullfile(root, "reports", "csv"));
mkdir(fullfile(root, "reports", "image"));
cleanup = onCleanup(@() rmdir(root, "s")); %#ok<NASGU>

components = ["prach","initial_access","ssb","pdcch","pdsch", ...
    "pusch","pucch","reference_signals","mimo","frame_grid", ...
    "waveform","l3","channel","rf","mac_harq_scheduler", ...
    "l2","traffic","validation"];
fixtureNames = ["prach_trials","initial_access_sib1","ssb_pbch_trials", ...
    "pdcch_dci_trials","pdsch_dlsch_trials","pusch_ulsch_trials", ...
    "pucch_uci_trials","rsla_reference_signal_trials", ...
    "mimo_beamforming_trials","frame_grid_slot_symbol_map", ...
    "waveform_spectrum","rrc_handover_trace","channel_geometry_state", ...
    "rf_agc_trace","mac_harq_trials","rlc_pdcp_bearer_trace", ...
    "traffic_qos_trace","validation_artifact_audit"];
for idx = 1:numel(fixtureNames)
    writetable(table((1:3).', 'VariableNames', {'Trial'}), ...
        fullfile(root, "reports", "csv", fixtureNames(idx) + ".csv"));
end
emptyRegistry = table('Size', [0 2], ...
    'VariableTypes', {'string','string'}, ...
    'VariableNames', {'FailureCode','FailureReason'});
writetable(emptyRegistry, fullfile(root, "reports", "csv", ...
    "prach_empty_failure_registry.csv"));
mkdir(fullfile(root, "packet_flow", "csv"));
writetable(table((1:3).', true(3, 1), ...
    'VariableNames', {'TransportBlockId','ProtocolDecodedBitExact'}), ...
    fullfile(root, "packet_flow", "csv", ...
    "protocol_in_path_payload_delivery.csv"));
writetable(table("fixture_scenario", string(repmat('a', 1, 64)), ...
    "waveform_bundle", true, 'VariableNames', ...
    {'ScenarioID','ConfigHash','RunnerProfile','ResultOk'}), ...
    fullfile(root, "reports", "csv", "scenario_summary.csv"));
mkdir(fullfile(root, "outputs", "fixture"));
sixgr.util.jsonWrite(fullfile(root, "outputs", "fixture", ...
    "artifact_manifest.json"), struct("ArtifactCount", 1));
sourcePNG = fullfile(root, "reports", "image", "prach_correlation.png");
imwrite(uint8(reshape(0:63, 8, 8)), sourcePNG);
sixgr.visual.writeComponentPlotLineage(root, ...
    fullfile(root, "reports", "csv", "prach_plot_lineage.csv"), ...
    "prach_correlation", sourcePNG, ...
    "reports/csv/prach_trials.csv", "tests.testLLSComponentArtifactViews", ...
    "SourcesAlreadyFinalized", true);
sourceSVG = fullfile(root, "reports", "image", "prach_legacy.svg");
fid = fopen(sourceSVG, "w");
assert(fid >= 0);
fprintf(fid, '<svg xmlns="http://www.w3.org/2000/svg"></svg>');
fclose(fid);
anchorDir = fullfile(root, "component_anchors", "prach", "control", "csv");
mkdir(anchorDir);
anchorPath = fullfile(anchorDir, "prach_anchor_only.csv");
writetable(table((1:2).', 'VariableNames', {'Trial'}), anchorPath);
childDir = fullfile(root, "sweeps", "point_1", "reports", "csv");
mkdir(childDir);
writetable(table((1:2).', 'VariableNames', {'Trial'}), ...
    fullfile(childDir, "pdsch_child_trials.csv"));

out = sixgr.truth.publishComponentArtifactViews(root, ...
    "Enabled", true, "Required", true);
assert(out.Ok);
assert(out.PublishedCount == 21, ...
    "All 18 component fixtures, the decoder-backed L2 payload table, plot lineage, and the PRACH PNG must be published.");
assert(out.MissingComponentCount == 0);
assert(out.SkippedLegacySVGCount == 1, ...
    "Legacy SVG must be counted and excluded from component views.");
assert(out.SkippedEmptyCSVCount == 1, ...
    "Header-only canonical registries must not be duplicated into component folders.");
assert(isfile(fullfile(root, "prach", "csv", "prach_trials.csv")));
assert(isfile(fullfile(root, "prach", "image", "prach_correlation.png")));
assert(isfile(fullfile(root, "l2", "csv", ...
    "protocol_in_path_payload_delivery.csv")), ...
    "Protocol decoder evidence must publish under l2.");
assert(~isfile(fullfile(root, "waveform", "csv", ...
    "protocol_in_path_payload_delivery.csv")), ...
    "Protocol decoder evidence must not be classified as waveform.");
assert(~isfile(fullfile(root, "prach", "image", "prach_legacy.svg")));
assert(~isfile(fullfile(root, "prach", "csv", ...
    "prach_empty_failure_registry.csv")), ...
    "A CSV without runtime observations must remain canonical-only.");
assert(~isfile(fullfile(root, "validation", "csv", "scenario_summary.csv")), ...
    "Mutable finalization-control artifacts must remain canonical-only.");
assert(~any(out.Rows.CanonicalRelativePath == ...
    "reports/csv/scenario_summary.csv"));
assert(~any(contains(out.Rows.CanonicalRelativePath, "artifact_manifest")));
assert(~any(startsWith(out.Rows.CanonicalRelativePath, "component_anchors/")), ...
    "Component-anchor evidence must never be republished as in-path component evidence.");
assert(~any(startsWith(out.Rows.CanonicalRelativePath, "sweeps/")), ...
    "A parent execution must never republish artifacts owned by a child sweep execution.");
assert(~isfile(fullfile(root, "prach", "csv", "prach_anchor_only.csv")));
for idx = 1:numel(components)
    assert(isfolder(fullfile(root, components(idx))), ...
        "Missing component folder: %s", components(idx));
    summaryRow = out.SummaryRows(out.SummaryRows.Component == components(idx), :);
    assert(height(summaryRow) == 1 && summaryRow.SourceArtifactCount >= 1);
    assert(summaryRow.ScenarioID == "fixture_scenario" && ...
        summaryRow.ConfigHash == string(repmat('a', 1, 64)) && ...
        summaryRow.RunnerProfile == "waveform_bundle", ...
        "Component summary rows must retain the canonical run identity.");
    assert(summaryRow.PublicationStatus == "PUBLISHED_HASH_VERIFIED");
end
assert(all(out.Rows.MirrorOnly));
assert(all(out.Rows.CanonicalAuthorityRetained));
assert(all(out.Rows.CanonicalSHA256 == out.Rows.PublishedSHA256));
assert(all(out.Rows.PublishStatus == "PUBLISHED_HASH_VERIFIED"));
assert(isfile(fullfile(root, "reports", "csv", ...
    "component_artifact_publication_manifest.csv")));
assert(isfile(fullfile(root, "reports", "csv", ...
    "component_artifact_publication_summary.csv")));
visual = sixgr.visual.verifyVisualArtifacts(root, table());
mirrorMask = replace(string(visual.ArtifactPath), "\", "/") == ...
    "prach/image/prach_correlation.png";
assert(sum(mirrorMask) == 1 && all(visual.IntegrityOk(mirrorMask)), ...
    "A hash-verified component image mirror must inherit the accepted canonical plot lineage.");
recursive = sixgr.validation.auditRunArtifacts(root, "Strict", false, ...
    "WriteOutputs", false, "FailOnUnmanifestedImages", true);
recursiveMirrorMask = string(recursive.ImageAuditTable.relative_path) == ...
    "prach/image/prach_correlation.png";
assert(sum(recursiveMirrorMask) == 1 && ...
    all(string(recursive.ImageAuditTable.status(recursiveMirrorMask)) == "pass") && ...
    all(string(recursive.ImageAuditTable.source_csv(recursiveMirrorMask)) == ...
    "reports/csv/prach_trials.csv"), ...
    "The recursive audit must resolve component-image lineage transitively through the hash-verified publication manifest.");

repeat = sixgr.truth.publishComponentArtifactViews(root, ...
    "Enabled", true, "Required", true);
assert(repeat.Ok && repeat.PublishedCount == out.PublishedCount, ...
    "Repeated publication must be deterministic and must not recurse into mirrors.");
assert(repeat.RemovedStaleMirrorCount == out.PublishedCount, ...
    "Repeated publication must safely replace all prior hash-verified mirrors.");

% Reproduce an orphan from a manifest older than the immediately prior one.
% The reserved hash-suffix name is publisher-owned but is intentionally not
% added to the current manifest.
orphanSource = fullfile(root, "reports", "csv", "prach_trials.csv");
orphanHash = string(sixgr.protocol.ProtocolHash.file(orphanSource));
orphanPath = fullfile(root, "prach", "csv", ...
    "prach_trials__" + extractBefore(orphanHash, 13) + ".csv");
copyfile(orphanSource, orphanPath);
assert(isfile(orphanPath));
withoutOrphan = sixgr.truth.publishComponentArtifactViews(root, ...
    "Enabled", true, "Required", true);
assert(~isfile(orphanPath), ...
    "An unmanifested publisher-owned hash-suffixed mirror must be removed.");
assert(withoutOrphan.RemovedStaleMirrorCount == repeat.PublishedCount + 1, ...
    "Cleanup must count prior-manifest mirrors and the orphan separately.");

deletedCanonical = fullfile(root, "reports", "csv", ...
    "validation_artifact_audit.csv");
deletedMirror = fullfile(root, "validation", "csv", ...
    "validation_artifact_audit.csv");
delete(deletedCanonical);
withoutStale = sixgr.truth.publishComponentArtifactViews(root, ...
    "Enabled", true, "Required", true);
assert(~isfile(deletedMirror), ...
    "A mirror whose canonical source disappeared must not survive republication.");
assert(withoutStale.PublishedCount == out.PublishedCount - 1);
assert(withoutStale.MissingComponentCount == 1);
assert(~withoutStale.Ok, ...
    "Required component publication must fail when canonical evidence is absent.");
validationSummary = withoutStale.SummaryRows( ...
    withoutStale.SummaryRows.Component == "validation", :);
assert(validationSummary.PublicationStatus == "NO_CANONICAL_ARTIFACTS");

for masterName = ["master_sinr_sweep.yaml", "master_geometry_based.yaml"]
    scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile(pwd, ...
        "simulator", "configs", "scenarios", masterName));
    assert(~logical(scenario.get( ...
        "output.component_artifact_views.enabled", ...
        false)), ...
        "%s must retire legacy result-file mirroring.", masterName);
    assert(~logical(scenario.get( ...
        "output.component_artifact_views.required", ...
        false)), ...
        "%s must not require the retired mirror publisher.", ...
        masterName);
    assert(string(scenario.get( ...
        "output.component_artifact_views.mirror_mode", ...
        "")) == ...
        "byte_identical_hash_verified", ...
        "%s must preserve the canonical byte-identity policy.", masterName);
    configuredComponents = string(scenario.get( ...
        "output.component_artifact_views.required_components", ...
        strings(0, 1)));
    assert(isequal(configuredComponents(:), components(:)), ...
        "%s must retain the migration taxonomy while the mirror is disabled.", ...
        masterName);
    assert(logical(scenario.get( ...
        "output.artifact_contract_engine.enabled", false)), ...
        "%s must enable the runtime-only contract artifact engine.", masterName);
    assert(string(scenario.get( ...
        "output.artifact_contract_engine.source_policy", "")) == ...
        "runtime_memory_only", ...
        "%s must prohibit legacy CSV/image inputs.", masterName);
    assert(string(scenario.get( ...
        "output.artifact_contract_engine.catalog_scope", "")) == ...
        "runtime_in_path", ...
        "%s must not bind a single run to multi-campaign phase-pack evidence.", ...
        masterName);
    assert(~logical(scenario.get( ...
        "output.artifact_contract_engine.allow_svg", true)), ...
        "%s must prohibit SVG output.", masterName);
    assert(string(scenario.get( ...
        "output.artifact_contract_engine.image_format", "")) == "none" && ...
        string(scenario.get( ...
        "output.artifact_contract_engine.raster_authority", "")) == ...
        "post_run_csv_contract_materializer", ...
        "%s must delegate every runtime raster to the CSV materializer.", ...
        masterName);
end
ok = true;
end
