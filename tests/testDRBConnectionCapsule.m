function ok=testDRBConnectionCapsule()
% Exact codec/config/Runtime gates; admission receipts are DECLARED unit inputs.
% Does not call or qualify the production RF/protocol receipt adapters.
s=struct('transaction_id',2,'cell_group_id',0,'drb_id',1,'lcid',4, ...
    'pdcp',struct('sn_size_ul',"len12bits",'sn_size_dl',"len18bits", ...
        'discard_timer',"ms100",'t_reordering',"ms40",'integrity_protection',false), ...
    'sdap',struct('pdu_session',1,'qfi',9,'header_ul',"present",'header_dl',"present",'default_drb',true), ...
    'rlc_am',struct('sn_size_ul',"size12",'sn_size_dl',"size18",'t_poll_retransmit',"ms45", ...
        'poll_pdu',"p16",'poll_byte',"kB25",'max_retx_threshold',"t8", ...
        't_reassembly',"ms35",'t_status_prohibit',"ms10"), ...
    'logical_channel',struct('priority',3,'prioritised_bit_rate',"kBps8", ...
        'bucket_size_duration',"ms100",'logical_channel_group',1,'scheduling_request_id',0, ...
        'logical_channel_sr_mask',false,'logical_channel_sr_delay_timer_applied',false));

message=sixgr.rrc.asn1.NRAccessMessageCodec.encode('reconfiguration',s);
connection=struct('ExecutionRunID',"capsule-component",'UEID',"cell1-42",'ServingCell',1, ...
    'RNTI',42,'ConfigurationEpoch',1,'SampleRateHz',1000,'ClockEpoch',1, ...
    'ConnectionReceiptSHA256',hash('original-component-connection'));
core=struct('UEID',connection.UEID,'ConfigurationEpoch',1,'SampleRateHz',1000,'ClockEpoch',1, ...
    'CipherAlgorithm',"NEA0",'IntegrityAlgorithm',"128-NIA2",'CipherKey',uint8(16:31), ...
    'IntegrityKey',uint8(0:15),'KeySource',"configured_preestablished_core_key");
a=sixgr.rrc.PendingDRBEndpoints(message,connection,core,{});
dl=a.directionalRuntime('DL');ul=a.directionalRuntime('UL');
reject(@()dl.enqueuePacket('before-issued',uint8([1 2]),.001),'sixgr:protocol:DRBEndpointNotAdmitted');
i=tx();issued=sixgr.rrc.projectDRBAdmissionPair(a,i,"issued");a.admitIssued(issued,20);
reject(@()ul.enqueuePacket('before-received',uint8([1 2]),.021),'sixgr:protocol:DRBEndpointNotAdmitted');
r=rx(false);received=sixgr.rrc.projectDRBAdmissionPair(a,r,"received");
bad=received;bad{2}.RNTI=43;bad{2}=seal(bad{2});
reject(@()a.admitReceived(bad,30),'sixgr:protocol:DRBAdmissionScope');
% Failed second-direction preflight cannot admit first-direction traffic.
reject(@()ul.enqueuePacket('still-disabled',uint8([1 2]),.030),'sixgr:protocol:DRBEndpointNotAdmitted');
a.admitReceived(received,30);
assert(a.directionalRuntime('DL')==dl&&a.directionalRuntime('UL')==ul);
ul.enqueuePacket('original-UL',uint8([1 2]),.031);before=ul.securityState();
a.admitReceived(received,32);after=ul.securityState();assert(after.TXCount==before.TXCount);
reject(@()dl.enqueuePacket('before-complete',uint8([3 4]),.032),'sixgr:protocol:DRBEndpointNotAdmitted');
c=rx(true);complete=sixgr.rrc.projectDRBAdmissionPair(a,c,"complete");a.admitComplete(complete,50);
dl.enqueuePacket('actual-DL-after-gate',uint8([3 4]),.051);
% Independent gNB Complete must not depend on this simulator's UE-local flag.
b=sixgr.rrc.PendingDRBEndpoints(message,connection,core,{});
bi=sixgr.rrc.projectDRBAdmissionPair(b,i,"issued");b.admitIssued(bi,20);
bc=sixgr.rrc.projectDRBAdmissionPair(b,c,"complete");b.admitComplete(bc,50);
bdl=b.directionalRuntime('DL');bul=b.directionalRuntime('UL');bdl.enqueuePacket('gNB-independent',uint8([5 6]),.051);
reject(@()bul.enqueuePacket('UE-not-admitted',uint8([5 6]),.051),'sixgr:protocol:DRBEndpointNotAdmitted');
fprintf('DRB_CONNECTION_CAPSULE_PASS same_handles=1 paired_preflight=1 declared_admission_inputs=1 RF=0\n');ok=true;
end
function o=tx()
o=struct('TransmitComponentID',"declared-tx",'TransmitEnqueueReceiptSHA256',hash('enqueue'), ...
    'OriginalComponentSampleSHA256',hash('samples'),'TransmitObservationSHA256',hash('tx'), ...
    'PhysicalTransmissionReceiptSHA256',hash('declared-physical-placeholder'), ...
    'ProtectedPDCPPDUSHA256',hash('DL-pdu'),'SecurityContextID',"DL-security", ...
    'IntegrityProtected',true,'TransmitStartSample',10,'TransmitEndSampleExclusive',18,'IssuedAtSample',20, ...
    'EvidenceBoundary',"declared_component_receipt_not_physical_proof");
end
function o=rx(complete)
o=struct('ReceiverObservationID',"declared-rx",'ReceiverObservationSHA256',hash('rx'), ...
    'ReceivedMACPayloadSHA256',hash('MAC'),'ProtectedPDCPPDUSHA256',hash('DL-pdu'), ...
    'SecurityContextID',"DL-security",'IntegrityVerified',true, ...
    'ObservationStartSample',9,'ObservationEndSampleExclusive',25,'AvailableAtSample',30, ...
    'EvidenceBoundary',"declared_component_receipt_not_physical_proof");
if complete
 encoded=sixgr.rrc.asn1.NRAccessMessageCodec.encode('reconfiguration_complete',struct('transaction_id',2));o.Payload=encoded.Bytes;
 o.ProtectedPDCPPDUSHA256=hash('UL-pdu');o.SecurityContextID="UL-security";
 o.ObservationStartSample=35;o.ObservationEndSampleExclusive=45;o.AvailableAtSample=50;
end
end
function h=hash(x),h=sixgr.protocol.ProtocolHash.bytes(uint8(x));end
function r=seal(r),r=rmfield(r,'SHA256');r.SHA256=sixgr.l2.mac.MACHash.of(r);end
function reject(f,id)
try,f();catch e,assert(string(e.identifier)==id,'test:UnexpectedError','Expected %s, got %s: %s',id,e.identifier,e.message);return;end
error('test:ExpectedError','Expected %s.',id);
end
