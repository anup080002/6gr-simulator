function ok=testH4AntennaPanelInventory()
% Runtime object inventory/export; not beam or waveform qualification.
setup6GRSimToolkit('Verbose',false);
root=fullfile(pwd,'logs','lls_repairs', ...
    ['h4_panel_inventory_' char(java.util.UUID.randomUUID)]);
scenario=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_adaptation.yaml');
cfg=sixgr.lls6g.buildInternalConfig(scenario,root);
layout=struct('bs',struct('pos_m',nan(1,3),'azim_deg',NaN));
users=struct('pos_m',nan(1,3),'heading_deg',NaN);
[bs,ue,T]=sixgr.truth.CoupledTruthRuntime.buildRuntimeAntennaStateForFixedLink( ...
    cfg,layout,users);
fields=["PanelRows","PanelCols","PanelCount","PolarizationAngles_deg"];
assert(all(ismember(fields,string(T.Properties.VariableNames))), ...
    'Runtime antenna metadata must retain actual panel and polarization inventory.');
objects={bs(1).Antenna,ue(1).Antenna};
for k=1:2
    a=objects{k};
    assert(T.PanelRows(k)==a.PanelRows && T.PanelCols(k)==a.PanelCols && ...
        T.PanelCount(k)==a.PanelCount);
    assert(string(T.PolarizationAngles_deg(k))==string(mat2str(a.PolarizationAngles_deg)));
    assert(T.NumRows(k)*T.NumCols(k)*T.NumPolarizations(k)*T.PanelCount(k)==T.NumElements(k));
end
assert(isequal(T.PanelCount,[2;1]) && isequal(T.NumElements,[64;4]) && ...
    all(T.NumPorts==4),'Physical panels must remain distinct from logical ports.');
assert(cfg.phy.csi.reportConfiguration.Panels==1, ...
    'Export must not relabel the logical Type-I Single-Panel CSI codebook.');
raw=struct('DL',table(),'UL',table());
artifacts=sixgr.truth.exportLLSLiveDerivedTables(cfg,root,raw,struct(), ...
    struct('AntennaConfigResolvedTable',T),struct());
published=readtable(artifacts.AntennaConfigResolvedPath, ...
    'TextType','string','VariableNamingRule','preserve');
assert(all(ismember(fields,string(published.Properties.VariableNames))) && ...
    isequal(published.PanelCount,T.PanelCount) && ...
    isequal(published.PolarizationAngles_deg,string(T.PolarizationAngles_deg)));
% Legacy observations without runtime panel evidence must not acquire
% configured panel counts merely because YAML declares them.
missing=removevars(T,fields);
absent=sixgr.truth.exportLLSLiveDerivedTables(cfg,fullfile(root,'missing'),raw, ...
    struct(),struct('AntennaConfigResolvedTable',missing),struct());
unmeasured=readtable(absent.AntennaConfigResolvedPath, ...
    'TextType','string','VariableNamingRule','preserve');
assert(all(isnan(unmeasured.PanelRows)) && all(isnan(unmeasured.PanelCols)) && ...
    all(isnan(unmeasured.PanelCount)));
assert(all(ismissing(unmeasured.PolarizationAngles_deg) | ...
    strlength(string(unmeasured.PolarizationAngles_deg))==0));
disp('H4_ANTENNA_PANEL_INVENTORY_PASS'); ok=true;
end
