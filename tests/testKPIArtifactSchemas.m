function ok = testKPIArtifactSchemas()
%TESTKPIARTIFACTSCHEMAS Exported KPI audit artifacts must have required schemas.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

raw = struct();
raw.UL = localDirectionTable("UL", 7.952);
raw.DL = localDirectionTable("DL", 40.137091);
kpiTable = table(["DL_PDSCH_Throughput"; "UL_PUSCH_Throughput"], [true; true], [false; false], ...
    'VariableNames', {'Case','Ok','Skipped'});
cfg = struct( ...
    "run", struct("strictMode", true, ...
        "scenarioID", "kpi_schema_fixture", "runTag", "kpi_run_fixture"), ...
    "lls6g", struct("resolvedConfig", struct("sweeps_and_matrix", struct( ...
        "fixed_link_calibration", struct("only", true)))), ...
    "phy", struct("harq", struct("enable", false)), ...
    "protocol", struct("enabled", false, "strict", false));
details = struct("RawTrials", raw, "Config", cfg);

sixgr.link.exportLinkKPIs(tmp, kpiTable, details, "SaveCSV", true, "SaveMAT", false, "SaveFigures", false);

reportDir = fullfile(tmp, "reports", "csv");
files = ["kpi_formula_registry.csv","kpi_source_table_manifest.csv", ...
    "kpi_raw_table_schema_audit.csv","kpi_reconstruction_summary.csv", ...
    "kpi_row_contributions_ul.csv","kpi_row_contributions_dl.csv", ...
    "kpi_harq_delivery_trace_ul.csv","kpi_harq_delivery_trace_dl.csv", ...
    "kpi_direction_isolation_audit.csv","kpi_legacy_alias_map.csv", ...
    "kpi_known_bug_regression.csv","kpi_unit_conversion_audit.csv", ...
    "kpi_duration_source_audit.csv","kpi_objective_binding.csv"];
for i = 1:numel(files)
    path = fullfile(reportDir, files(i));
    assert(exist(path, "file") == 2, "Missing KPI artifact: %s", files(i));
    T = readtable(path, "VariableNamingRule", "preserve");
    assert(istable(T) && width(T) > 0, "KPI artifact has no schema columns: %s", files(i));
end

recon = readtable(fullfile(reportDir, "kpi_reconstruction_summary.csv"), "VariableNamingRule", "preserve");
requiredRecon = ["KPIName","Direction","FormulaId","SourceRowsHash","ReconciliationPass","StrictOk"];
assert(all(ismember(requiredRecon, string(recon.Properties.VariableNames))), ...
    "KPI reconstruction summary is missing required contract columns.");
assert(all(ismember(["NoTransmissionEvidenceHash","NoTransmissionEvidencePaths"], ...
    string(recon.Properties.VariableNames))), ...
    "Blank provenance columns are part of the declared KPI schema, not removable fields.");
assert(all(ismember(["FailureReason","ModifiedTime"], ...
    string(sixgr.util.csvReadTable(fullfile(reportDir,"kpi_source_table_manifest.csv")).Properties.VariableNames))), ...
    "KPI manifests must retain declared unavailable-value columns.");

manifest = readtable(fullfile(reportDir, "kpi_source_table_manifest.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
assert(all(ismember(["DLSubsetRowCount","DLSubsetRowsHash", ...
    "ULSubsetRowCount","ULSubsetRowsHash"], ...
    string(manifest.Properties.VariableNames))), ...
    "KPI source manifests must expose direction-scoped count/hash bindings for mixed-direction sources.");
assert(ismember("ScenarioName", string(manifest.Properties.VariableNames)) && ...
    all(string(manifest.ScenarioName) == "kpi_schema_fixture"), ...
    "KPI source manifests must inherit scenario identity from details.Config when no duplicate top-level alias is supplied.");
assert(ismember("RunId", string(manifest.Properties.VariableNames)) && ...
    all(string(manifest.RunId) == "kpi_run_fixture"), ...
    "KPI run identity must come from the run tag and must never be replaced by the scenario identity.");
for direction = ["DL","UL"]
    row = manifest(string(manifest.Direction) == direction, :);
    expectedPath = "air_interface/csv/" + lower(direction) + ...
        string(localTernary(direction == "DL", "_pdsch_trials.csv", "_pusch_trials.csv"));
    source = raw.(char(direction));
    assert(height(row) == 1 && string(row.SourceTablePath) == expectedPath, ...
        "KPI source manifest must name the canonical table actually consumed, not a fixed-link alias.");
    assert(double(row.RowCount) == height(source) && ...
        double(row.ColumnCount) == width(source) && ...
        string(row.FileHash) == sixgr.kpi.hashKPISourceRows(source), ...
        "KPI source manifest dimensions/hash must describe the exact consumed table.");
end

for direction = ["PacketSDU","ApplicationPackets","HARQTimeline", ...
        "ULGrants","DLGrants","SlotTrace"]
    row = manifest(string(manifest.Direction) == direction, :);
    assert(height(row) == 1 && ~logical(row.RequiredForObjective), ...
        "Disabled fixed-link protocol/HARQ/scheduler sources must be explicitly non-required.");
end

binding = readtable(fullfile(reportDir, "kpi_objective_binding.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
disabledNames = ["UL_MAC_Goodput_Mbps","DL_MAC_Goodput_Mbps", ...
    "UL_Application_Goodput_Mbps","DL_Application_Goodput_Mbps", ...
    "UL_HARQ_NACK_Rate","DL_HARQ_NACK_Rate", ...
    "UL_Retransmission_Rate","DL_Retransmission_Rate", ...
    "UL_PRB_Utilization","DL_PRB_Utilization"];
disabled = binding(ismember(string(binding.KPIName), disabledNames), :);
assert(height(disabled) == numel(disabledNames) && ...
    all(~logical(disabled.Applicable)) && ...
    all(lower(string(disabled.Status)) == "not_applicable") && ...
    all(strlength(strtrim(string(disabled.ApplicabilityReason))) > 0), ...
    "Feature-disabled KPI bindings must be not-applicable with an explicit resolved-config reason.");

ok = true;
end

function value = localTernary(condition, ifTrue, ifFalse)
if condition
    value = ifTrue;
else
    value = ifFalse;
end
end

function T = localDirectionTable(direction, goodput)
T = table( ...
    repmat(string(direction), 2, 1), [goodput; 0], [true; false], [0; 1], [1000; 1000], ...
    [1000; 1000], [1000; 0], [1; 1], [1; 2], string([direction + "_tb_1"; direction + "_tb_2"]), ...
    [0; 0], [0; 0], [0; 1], [1; 1], [1; 2], ...
    'VariableNames', {'Direction','Goodput_Mbps','CRCPass','BitErrors','BitsCompared', ...
    'TBSize_bits','GoodBits','Frame','Slot','TransportBlockId','HARQProcessId','RV','NDI', ...
    'AirInterfaceObservation_ms','TrialId'});
end
