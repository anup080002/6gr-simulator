function ok = testKPIRawToSummaryReconstruction()
%TESTKPIRAWTOSUMMARYRECONSTRUCTION Exporter must write raw-derived KPI summary.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

raw = localRawFixture();
kpiTable = table(["DL_PDSCH_Throughput"; "UL_PUSCH_Throughput"], [true; true], [false; false], ...
    'VariableNames', {'Case','Ok','Skipped'});
details = struct("RawTrials", raw, "Config", struct("run", struct("strictMode", true)));

sixgr.link.exportLinkKPIs(tmp, kpiTable, details, ...
    "SaveCSV", true, "SaveMAT", false, "SaveFigures", false);

summaryPath = fullfile(tmp, "csv", "lls_kpi_summary.csv");
assert(exist(summaryPath, "file") == 2, "LLS KPI summary CSV must be written.");
summary = readtable(summaryPath, "VariableNamingRule", "preserve");
assert(abs(double(summary.Goodput_UL_max_Mbps(1)) - 7.952) < 1e-9, ...
    "Exported UL legacy goodput alias must come from raw UL rows.");
assert(abs(double(summary.Goodput_DL_max_Mbps(1)) - 40.137091) < 1e-9, ...
    "Exported DL legacy goodput alias must come from raw DL rows.");

reportDir = fullfile(tmp, "reports", "csv");
required = ["kpi_formula_registry.csv","kpi_reconstruction_summary.csv", ...
    "kpi_direction_isolation_audit.csv","kpi_legacy_alias_map.csv", ...
    "kpi_known_bug_regression.csv","kpi_row_contributions_ul.csv", ...
    "kpi_harq_delivery_trace_ul.csv","kpi_unit_conversion_audit.csv", ...
    "kpi_duration_source_audit.csv"];
for i = 1:numel(required)
    assert(exist(fullfile(reportDir, required(i)), "file") == 2, ...
        "Missing KPI audit artifact: %s", required(i));
end

knownBug = readtable(fullfile(reportDir, "kpi_known_bug_regression.csv"), "VariableNamingRule", "preserve");
assert(logical(knownBug.BugPrevented(1)) && ~logical(knownBug.BugDetected(1)), ...
    "Known KPI copy regression artifact must show BugPrevented=true.");

aliasMap = readtable(fullfile(reportDir, "kpi_legacy_alias_map.csv"), "VariableNamingRule", "preserve");
ulAlias = aliasMap(string(aliasMap.LegacyAliasName) == "Goodput_UL_max_Mbps", :);
assert(height(ulAlias) == 1 && logical(ulAlias.Equal(1)), ...
    "UL legacy alias must map exactly to the canonical formula value.");

ok = true;
end

