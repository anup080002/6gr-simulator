function rows=diagnosePDSCHCPWindowReplay(capturePaths,outputCSV,policy)
% Matched receiver-policy comparison on immutable received waveforms.
% Not a campaign result, a statistical BLER estimate or production acceptance.
arguments
    capturePaths (:,1) string
    outputCSV (1,1) string
    policy (1,1) struct
end
rows=table();
for file=capturePaths.'
    saved=load(file,'ReceiverReplay'); c=saved.ReceiverReplay; old=c.ReceiverResult;
    assert(any(c.Direction==["DL","UL"]) && c.Contract=="exact_receiver_replay/v1");
    assert(c.WaveformSHA256==string(sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(c.Waveform)));
    cfg=c.Config;
    cfg.phy.impairments.cfoCPObservation=policy;
    source=cfg.lls6g.resolvedConfig;
    source.impairments.cfo_cp_observation_policy=char(policy.Policy);
    source.impairments.cfo_cp_window_fraction=policy.WindowFraction;
    source.impairments.cfo_cp_false_alarm_probability=policy.FalseAlarmProbability;
    cfg.lls6g.resolvedConfig=source; cfg.lls6g.impairments=source.impairments;
    cfg.meta.configHash=char(sixgr.lls6g.config.hashResolvedScenario(source));
    cfg=sixgr.config.installRuntimeOperatingAuthority(cfg,source);
    baseline=feval(c.ReceiverFunction,c.Waveform,c.Config,c.ReceiverArguments{:});
    assert(isequal(baseline.TransportBlock,old.TransportBlock) && baseline.TBCRCPass==old.TBCRCPass && ...
        baseline.CFOCorrectionApplied_Hz==old.CFOCorrectionApplied_Hz, ...
        'The unmodified receiver policy must reproduce retained evidence.');
    rx=feval(c.ReceiverFunction,c.Waveform,cfg,c.ReceiverArguments{:});
    if c.Direction=="DL", dataChannel='PDSCH'; else, dataChannel='PUSCH'; end
    assigned=rx.(dataChannel); originalAssigned=baseline.(dataChannel);
    assert(rx.AppliedTimingCorrection_samples==baseline.AppliedTimingCorrection_samples && ...
        assigned.NumLayers==originalAssigned.NumLayers && ...
        isequal(assigned.PRBSet,originalAssigned.PRBSet) && ...
        isequal(assigned.DMRS,originalAssigned.DMRS), ...
        'Do not substitute timing, rank, PRBs or DMRS in the CFO comparison.');
    % Only post-reception scoring receives the retained transmitted bits.
    if c.Direction=="DL"
        ref=sixgr.phy.dl.PDSCH_Tx(c.Config,'ExecutionProfile','phy_calibration', ...
            'Carrier',old.Carrier,'PDSCH',old.PDSCH, ...
            'TransportBlockBits',c.Context.ScoringOnlyTransmittedBits, ...
            'NumTxAnt',c.Config.channel.nTxAnt);
    else
        ref=sixgr.phy.ul.PUSCH_Tx(c.Config, ...
            'Carrier',old.Carrier,'PUSCH',old.PUSCH, ...
            'TransportBlockBits',c.Context.ScoringOnlyTransmittedBits, ...
            'NumTxAnt',c.Config.channel.nTxAnt);
    end
    [before,~]=sixgr.link.deriveModulationTrackingMetrics(ref,baseline,c.Config,c.Direction);
    [after,~]=sixgr.link.deriveModulationTrackingMetrics(ref,rx,cfg,c.Direction);
    e=rx.CFOObservation;
    row=table(file,string(c.WaveformSHA256),c.Context.ConfiguredSNR_dB,c.Context.Slot, ...
        string(assigned.Modulation),double(assigned.NumLayers),double(ref.TransportBlockSize), ...
        logical(baseline.TBCRCPass),logical(rx.TBCRCPass), ...
        baseline.CFOCorrectionApplied_Hz,rx.CFOCorrectionApplied_Hz, ...
        before.EVM_rms,after.EVM_rms,e.ObservationCoherenceSquared, ...
        e.ObservationStartFromUsefulSymbol_samples,e.ObservationLength_samples, ...
        string(cfg.meta.configHash),false, ...
        'VariableNames',{'CaptureMAT','WaveformSHA256','ConfiguredSNR_dB','Slot', ...
        'Modulation','Layers','TBSBits','BaselineCRCPass','CandidateCRCPass', ...
        'BaselineCFO_Hz','CandidateCFO_Hz','BaselineEVM_rms','CandidateEVM_rms', ...
        'CPCoherenceSquared','CPWindowStartFromUsefulSymbol_samples','CPWindowLength_samples', ...
        'CandidateConfigHash','StatisticallyQualified'});
    rows=[rows;row]; %#ok<AGROW>
    sixgr.util.csvWriteTable(outputCSV,rows,'PreserveSchema',true,'RoundTripNumericText',true);
end
end
