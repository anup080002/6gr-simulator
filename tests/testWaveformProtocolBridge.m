function ok = testWaveformProtocolBridge()
%TESTWAVEFORMPROTOCOLBRIDGE Exact protocol bytes fill one PHY transport block.

setup6GRSimToolkit("Verbose", false);
cfg = localProtocolConfig();
bridge = sixgr.protocol.WaveformProtocolBridge(cfg, 2);
tbsBits = 1024;
payloadBytes = bridge.maximumPayloadBytes(tbsBits);
assert(payloadBytes > 0);
payload = uint8(mod(0:(payloadBytes-1), 256));
[bits, evidence] = bridge.encodeFragment(1, "DL", "tb-dl-1", ...
    "flow-DL-UE-001-fragment-1", payload, tbsBits, 0.001);
assert(numel(bits) == tbsBits && all(bits == 0 | bits == 1));
assert(evidence.PayloadBits == payloadBytes * 8);
assert(evidence.MACPDUBytes == tbsBits / 8);
assert(evidence.SameWaveformPayloadTruth);
assert(strlength(evidence.PayloadSHA256) == 64 && strlength(evidence.MACSHA256) == 64);
[delivered, deliveryEvidence] = bridge.deliverDecoded("tb-dl-1", bits, 0.002);
assert(delivered && deliveryEvidence.Status == "delivered_after_exact_phy_decode");
assert(deliveryEvidence.DecodedBitExact && ...
    deliveryEvidence.DecodedMACSHA256 == evidence.MACSHA256 && ...
    deliveryEvidence.DecodedRLC_SHA256 == evidence.EncodedRLC_SHA256);
[duplicate, duplicateEvidence] = bridge.deliverDecoded("tb-dl-1", bits, 0.003);
assert(~duplicate && duplicateEvidence.Status == "duplicate_harq_delivery_rejected");

[corruptBits, ~] = bridge.encodeFragment(1, "DL", "tb-dl-corrupt", ...
    "flow-DL-UE-001-fragment-corrupt", payload, tbsBits, 0.004);
corruptBits(1) = 1 - corruptBits(1);
didThrow = false;
try
    bridge.deliverDecoded("tb-dl-corrupt", corruptBits, 0.005);
catch ME
    didThrow = strcmp(ME.identifier, ...
        "sixgr:protocol:DecodedTransportBlockMismatch");
end
assert(didThrow, ...
    "A CRC-pass claim with altered decoder bytes must fail closed.");

didThrow = false;
try
    bridge.encodeFragment(1, "UL", "tb-bad", ...
        "flow-UL-UE-001-fragment-1", uint8(1), 1001, 0.006);
catch ME
    didThrow = strcmp(ME.identifier, "sixgr:protocol:NonByteAlignedTransportBlock");
end
assert(didThrow);

% The coordinator must refuse a protocol/TB binding whose immutable
% segment identity no longer agrees with the application ledger.
packet = struct( ...
    "Direction", "DL", "UEIndex", 1, "RNTI", 1001, ...
    "PacketId", "DL_ue1_frame1_pkt1", ...
    "ApplicationPacketId", "DL_ue1_frame1_pkt1", ...
    "OfferedBits", 64, "RemainingBits", 64, ...
    "DeliverySuccess", false, "EnqueueTime_s", 0);
state = struct( ...
    "NumUsers", 1, "ProtocolWaveformEnabled", true, ...
    "PacketDeliveryLedgerTable", struct2table(packet, "AsArray", true), ...
    "PacketSDULedgerTable", table(), ...
    "DLQueueBits", 64, "DLTransmittedBits", 0, ...
    "MultiUser", struct("RNTIStart", 1001), ...
    "CurrentSlot", 16, "CurrentFrame", 1, "SlotDuration_s", 0.5e-3, ...
    "DLGrantTraceTable", table(), "ULGrantTraceTable", table());
badGrant = struct( ...
    "TBSBits", 128, "RNTI", 1001, "UEIndex", 1, "Slot", 16, "Frame", 1, ...
    "ProtocolPayloadSameWaveformTruth", true, ...
    "ProtocolPacketId", char(packet.PacketId), ...
    "ProtocolPayloadBits", 64, "ProtocolSegmentIndex", 2, ...
    "ProtocolPayloadOffsetBits", 0, ...
    "HARQ", struct("IsRetransmission", false, "HarqID", 0, "NDI", 1, "RV", 0));
didThrow = false;
try
    sixgr.truth.CoupledTruthRuntime.commitGrantExecution(state, 1, "DL", badGrant);
catch ME
    didThrow = strcmp(ME.identifier, "sixgr:protocol:ProtocolGrantLedgerDivergence");
end
assert(didThrow, ...
    "A mismatched protocol segment/offset/payload binding must fail closed.");
ok = true;
end

function cfg = localProtocolConfig()
cfg = struct();
cfg.enabled = true;
cfg.strict = true;
cfg.configuration_epoch = 1;
cfg.rlc = struct("sn_bits",18,"poll_pdu",16,"poll_byte",65536, ...
    "max_retx_threshold",8);
cfg.pdcp = struct("sn_bits",18,"cipher_algorithm","NEA0", ...
    "integrity_algorithm","NIA0");
cfg.sdap = struct("pdu_session_id",1, ...
    "qfi_to_drb",struct("qfi",9,"drb_id",1));
cfg.mac = struct("lcid",4);
cfg.traffic.sessions = struct("flow_id","data-1","pdu_session_id",1, ...
    "qfi",9,"direction","BIDIR");
end
