function ok = testCarrierAggregationFrameTiming()
%TESTCARRIERAGGREGATIONFRAMETIMING CC identity and namespace isolation.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
[cc0, dl0] = localCarrier0();
[cc1, dl1] = localCarrier1();
policy = struct( ...
    "AllowedK0", [0, 1, 2], ...
    "AllowedK1", [1, 2, 4], ...
    "AllowedK2", [1, 2, 4], ...
    "PolicyID", "carrier_aggregation_timing_rows", ...
    "Source", "validated_test_policy");
engine = sixgr.phy.frame.TimingRelationEngine({cc0, cc1}, policy);

source = sixgr.phy.frame.AbsoluteTime.fromFrameSlotSymbol(0, 0, 0, dl0);
request = struct( ...
    "TestID", "cross-carrier-pdsch", ...
    "Procedure", "PDSCH", ...
    "SourceTime", source, ...
    "SchedulingCCID", "CC0", ...
    "ScheduledCCID", "CC1", ...
    "CarrierIndicator", 1, ...
    "SourceBWPID", "DL0", ...
    "TargetBWPID", "DL1", ...
    "SourceNumSymbols", 1, ...
    "TargetStartSymbol", 2, ...
    "TargetNumSymbols", 10, ...
    "MinimumProcessingSymbols", 0, ...
    "ProcessingTimeReference", "source", ...
    "HARQProcessID", 5, ...
    "K0", 2);
result = engine.resolvePDSCH(request);
assert(result.Valid && result.SchedulingCCID == "CC0" && ...
    result.ScheduledCCID == "CC1" && result.TargetBWPID == "DL1");
assert(result.SourceMu == 1 && result.TargetMu == 2 && ...
    result.TargetAbsoluteSlot == 2, ...
    "Cross-carrier mixed numerology must resolve on the scheduled CC grid.");

badIndicator = request;
badIndicator.TestID = "wrong-carrier-indicator";
badIndicator.CarrierIndicator = 0;
bad = engine.resolvePDSCH(badIndicator);
assert(~bad.Valid && ...
    bad.ReasonCode == "carrier_indicator_target_mismatch");

grid0 = cc0.createResourceGrid("DL0", "DL", 1);
grid1 = cc1.createResourceGrid("DL1", "DL", 1);
assert(isequal(size(grid0), [3276, 14]) && ...
    isequal(size(grid1), [780, 14]), ...
    "Each component carrier must own an independent resource grid.");

% Materialize a real PDSCH allocation on each component carrier.  The
% grids below are not shape-only zero placeholders: every occupied RE is
% returned by the 5G Toolbox indices used by the production materializer.
[carrier0, pdsch0] = localToolboxPDSCH(30, 273, 17, 0:23, [2, 10]);
[carrier1, pdsch1] = localToolboxPDSCH(60, 65, 29, 12:35, [1, 11]);
allocation0 = sixgr.phy.frame.ChannelAllocationMaterializer. ...
    materializePDSCH(carrier0, pdsch0, ...
    "CCID", 0, "BWPID", 0, "AbsoluteSlot", 2, ...
    "GridID", "CC0|DL0", "TestID", "ca_cc0_pdsch");
allocation1 = sixgr.phy.frame.ChannelAllocationMaterializer. ...
    materializePDSCH(carrier1, pdsch1, ...
    "CCID", 1, "BWPID", 1, "AbsoluteSlot", 2, ...
    "GridID", "CC1|DL1", "TestID", "ca_cc1_pdsch");
assert(allocation0.Exact && allocation1.Exact);
grid0 = localMapAllocation(grid0, allocation0, 1 + 2i, -1 + 1i);
grid0BeforeCC1 = grid0;
grid1 = localMapAllocation(grid1, allocation1, 3 - 1i, -2 - 2i);
assert(isequaln(grid0, grid0BeforeCC1), ...
    "Mapping CC1 resources mutated the independent CC0 grid.");
assert(isequal(find(grid0 ~= 0), localOccupiedIndices(allocation0)));
assert(isequal(find(grid1 ~= 0), localOccupiedIndices(allocation1)));

% Generate and round-trip both independently populated waveforms.  The
% numerologies intentionally differ, so waveform sample counts and OFDM
% configurations remain component-carrier local.
waveform0 = nrOFDMModulate(carrier0, grid0, "Windowing", 0);
waveform1 = nrOFDMModulate(carrier1, grid1, "Windowing", 0);
assert(~isempty(waveform0) && ~isempty(waveform1));
recovered0 = nrOFDMDemodulate(carrier0, waveform0);
recovered1 = nrOFDMDemodulate(carrier1, waveform1);
assert(localNMSE(grid0, recovered0) <= 1e-12);
assert(localNMSE(grid1, recovered1) <= 1e-12);
assert(size(waveform0, 1) ~= size(waveform1, 1), ...
    "Independent 30/60 kHz CC waveforms unexpectedly shared one timeline.");

key0 = cc0.resourceKey("DL0", "DL", "PDSCH", "grant-5");
key1 = cc1.resourceKey("DL1", "DL", "PDSCH", "grant-5");
assert(key0 ~= key1 && contains(key0, "CC=CC0") && ...
    contains(key1, "CC=CC1"));

cc0.putHARQState("DL", 5, struct("Payload", "cc0"));
cc1.putHARQState("DL", 5, struct("Payload", "cc1"));
[h0, found0] = cc0.getHARQState("DL", 5);
[h1, found1] = cc1.getHARQState("DL", 5);
assert(found0 && found1 && string(h0.Payload) == "cc0" && ...
    string(h1.Payload) == "cc1");
assert(cc0.harqKey("DL", 5) ~= cc1.harqKey("DL", 5), ...
    "HARQ process IDs must be namespaced by component carrier.");

cc0.putMeasurementState("RSRP", struct("Value", -80));
cc1.putMeasurementState("RSRP", struct("Value", -95));
[m0, mf0] = cc0.getMeasurementState("RSRP");
[m1, mf1] = cc1.getMeasurementState("RSRP");
assert(mf0 && mf1 && m0.Value == -80 && m1.Value == -95, ...
    "Measurement state must not leak between component carriers.");

for mu = 0:6
    spec = localNumerology(15 * 2^mu, "normal");
    exactSpec = sixgr.phy.frame.AbsoluteTime.resolveNumerology(spec);
    toolboxCarrier = nrCarrierConfig;
    toolboxCarrier.SubcarrierSpacing = spec.SubcarrierSpacingKHz;
    toolboxCarrier.CyclicPrefix = "normal";
    toolboxCarrier.NSizeGrid = 20;
    toolboxInfo = nrOFDMInfo(toolboxCarrier, "Nfft", 4096);
    toolboxTicks = int64(round(double(toolboxInfo.SymbolLengths(:).') * ...
        480 / spec.SubcarrierSpacingKHz));
    assert(isequal(exactSpec.SymbolLengthsTicks( ...
        1:numel(toolboxTicks)), toolboxTicks), ...
        "Physical CP-OFDM boundaries differ from nrOFDMInfo at mu=%d.", mu);
    slot = spec.SlotsPerFrame - 1;
    symbol = spec.SymbolsPerSlot - 1;
    exact = sixgr.phy.frame.AbsoluteTime.fromFrameSlotSymbol( ...
        10000, slot, symbol, spec);
    [frameBack, slotBack, symbolBack] = exact.toNumerology(spec);
    assert(frameBack == 10000 && slotBack == slot && ...
        symbolBack == symbol, ...
        "Integer timeline drift detected at mu=%d.", mu);
end
extended = localNumerology(60, "extended");
extendedSpec = sixgr.phy.frame.AbsoluteTime.resolveNumerology(extended);
toolboxCarrier = nrCarrierConfig;
toolboxCarrier.SubcarrierSpacing = 60;
toolboxCarrier.CyclicPrefix = "extended";
toolboxCarrier.NSizeGrid = 20;
toolboxInfo = nrOFDMInfo(toolboxCarrier, "Nfft", 4096);
toolboxTicks = int64(round(double(toolboxInfo.SymbolLengths(:).') * 8));
assert(isequal(extendedSpec.SymbolLengthsTicks( ...
    1:numel(toolboxTicks)), toolboxTicks), ...
    "Extended-CP physical boundaries differ from nrOFDMInfo.");
exactExtended = sixgr.phy.frame.AbsoluteTime.fromFrameSlotSymbol( ...
    10000, extended.SlotsPerFrame - 1, ...
    extended.SymbolsPerSlot - 1, extended);
[frameBack, slotBack, symbolBack] = ...
    exactExtended.toNumerology(extended);
assert(frameBack == 10000 && ...
    slotBack == extended.SlotsPerFrame - 1 && ...
    symbolBack == extended.SymbolsPerSlot - 1);
frame10000 = sixgr.phy.frame.AbsoluteTime.fromFrameSlotSymbol( ...
    10000, 0, 0, localNumerology(15, "normal"));
assert(frame10000.tickValue() == int64(10000) * ...
    sixgr.phy.frame.AbsoluteTime.TicksPerFrame);

trace = engine.traceTable();
assert(height(trace) == 2 && trace.Valid(1) && ~trace.Valid(2));
tmp = string(tempname);
mkdir(tmp);
cleanup = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>
csvPath = fullfile(tmp, "component_carrier_trace.csv");
writetable(trace, csvPath);
assert(isfile(csvPath) && dir(csvPath).bytes > 0);
imagePath = fullfile(tmp, "component_carrier_resource_map.png");
fig = figure("Visible", "off");
figCleanup = onCleanup(@() close(fig)); %#ok<NASGU>
bar(categorical(["CC0/DL0", "CC1/DL1"]), ...
    [size(grid0, 1), size(grid1, 1)]);
ylabel("resource-grid subcarriers");
title("Independent component-carrier resource maps");
grid on;
exportgraphics(fig, imagePath, "Resolution", 120);
assert(isfile(imagePath) && dir(imagePath).bytes > 1000);

ok = true;
end

function [cc, dl] = localCarrier0()
grid = struct("NStartGrid", 0, "NSizeGrid", 273, ...
    "SubcarrierSpacingKHz", 30, "FrequencyRange", "FR1");
zero = sixgr.phy.frame.AbsoluteTime.fromTicks(0);
dl = sixgr.phy.frame.BWPConfig(localBWP( ...
    "CC0", "CELL0", "DL0", "DL", 30, 273, true, ...
    zero, "DL0", "DL0"), grid);
ul = sixgr.phy.frame.BWPConfig(localBWP( ...
    "CC0", "CELL0", "UL0", "UL", 30, 273, true, ...
    zero, "DL0", "UL0"), grid);
map(1) = struct("Indicator", 0, "ScheduledCCID", "CC0");
map(2) = struct("Indicator", 1, "ScheduledCCID", "CC1");
cfg = localCC("CC0", "CELL0", 3.5e9, 100, 273, "CC0", map);
cc = sixgr.phy.frame.ComponentCarrierConfig(cfg, {dl, ul});
end

function [cc, dl] = localCarrier1()
grid = struct("NStartGrid", 0, "NSizeGrid", 65, ...
    "SubcarrierSpacingKHz", 60, "FrequencyRange", "FR1");
zero = sixgr.phy.frame.AbsoluteTime.fromTicks(0);
dl = sixgr.phy.frame.BWPConfig(localBWP( ...
    "CC1", "CELL1", "DL1", "DL", 60, 65, true, ...
    zero, "DL0", "DL1"), grid);
ul = sixgr.phy.frame.BWPConfig(localBWP( ...
    "CC1", "CELL1", "UL1", "UL", 60, 65, true, ...
    zero, "DL1", "UL1"), grid);
map = struct("Indicator", 0, "ScheduledCCID", "CC1");
cfg = localCC("CC1", "CELL1", 3.7e9, 50, 65, ...
    ["CC0", "CC1"], map);
cc = sixgr.phy.frame.ComponentCarrierConfig(cfg, {dl, ul});
end

function cfg = localBWP(ccid, cellID, id, direction, scs, sizeRB, ...
        active, activation, controlBWPID, dataBWPID)
cfg = struct( ...
    "BWPID", id, ...
    "Direction", direction, ...
    "CCID", ccid, ...
    "ServingCellID", cellID, ...
    "FrequencyRange", "FR1", ...
    "SCSKHz", scs, ...
    "CyclicPrefix", "normal", ...
    "NStartBWP", 0, ...
    "NSizeBWP", sizeRB, ...
    "ControlConfigRef", lower(direction) + "_control_" + id, ...
    "DataConfigRef", lower(direction) + "_data_" + id, ...
    "ControlBWPID", controlBWPID, ...
    "DataBWPID", dataBWPID, ...
    "ActiveInitial", active, ...
    "SwitchActivationTime", activation, ...
    "StateVersion", 1, ...
    "CommonTDDReferenceSCSKHz", NaN);
end

function cfg = localCC(ccid, cellID, centerHz, bandwidthMHz, nrb, ...
        schedulingCCIDs, indicatorMap)
cfg = struct( ...
    "CCID", ccid, ...
    "ServingCellID", cellID, ...
    "SchedulingCCIDs", schedulingCCIDs, ...
    "CenterFrequencyHz", centerHz, ...
    "DLCenterFrequencyHz", centerHz, ...
    "ULCenterFrequencyHz", centerHz - 100e6, ...
    "Band", "n77", ...
    "FrequencyRange", "FR1", ...
    "ChannelBandwidthMHz", bandwidthMHz, ...
    "DuplexMode", "FDD", ...
    "DLCarrierGrid", struct("NStartGrid", 0, "NSizeGrid", nrb, ...
    "SubcarrierSpacingKHz", localCarrierSCS(nrb)), ...
    "ULCarrierGrid", struct("NStartGrid", 0, "NSizeGrid", nrb, ...
    "SubcarrierSpacingKHz", localCarrierSCS(nrb)), ...
    "CarrierIndicatorMap", indicatorMap);
end

function scs = localCarrierSCS(nrb)
if nrb == 273
    scs = 30;
else
    scs = 60;
end
end

function num = localNumerology(scs, cp)
num = sixgr.phy.frame.NumerologyCatalog.resolve( ...
    scs, cp, "generic_waveform_test", "");
end

function [carrier, pdsch] = localToolboxPDSCH( ...
        scsKHz, nSizeGrid, nCellID, prbSet, symbolAllocation)
carrier = nrCarrierConfig;
carrier.NCellID = nCellID;
carrier.SubcarrierSpacing = scsKHz;
carrier.CyclicPrefix = "normal";
carrier.NSizeGrid = nSizeGrid;
carrier.NStartGrid = 0;
carrier.NFrame = 0;
carrier.NSlot = 2;

pdsch = nrPDSCHConfig;
pdsch.NSizeBWP = nSizeGrid;
pdsch.NStartBWP = 0;
pdsch.PRBSet = prbSet;
pdsch.SymbolAllocation = symbolAllocation;
pdsch.MappingType = "A";
pdsch.Modulation = "QPSK";
pdsch.NumLayers = 1;
pdsch.NID = nCellID;
pdsch.RNTI = 41;
end

function grid = localMapAllocation(grid, allocation, dataValue, dmrsValue)
data = double(allocation.Data.Indices1Based(:));
dmrs = double(allocation.DMRS.Indices1Based(:));
assert(~isempty(data) && ~isempty(dmrs));
grid(data) = dataValue;
grid(dmrs) = dmrsValue;
end

function indices = localOccupiedIndices(allocation)
indices = unique([double(allocation.Data.Indices1Based(:)); ...
    double(allocation.DMRS.Indices1Based(:))]);
end

function value = localNMSE(reference, observed)
assert(isequal(size(reference), size(observed)));
value = sum(abs(observed(:) - reference(:)).^2) / ...
    max(sum(abs(reference(:)).^2), eps);
end
