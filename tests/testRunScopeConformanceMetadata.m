function ok = testRunScopeConformanceMetadata()
%TESTRUNSCOPECONFORMANCEMETADATA Run metadata must expose scope/completion/conformance honestly.

setup6GRSimToolkit("Verbose", false);

tmp = fullfile(pwd,'results','e2e','scope_conformance_regression', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(tmp);
% Retain decoded access, grants and metadata on success and on failure.
fprintf('SCOPE_CONFORMANCE_EVIDENCE_ROOT=%s\n',tmp);
window=sixgr.lls6g.config.readConfigFile(fullfile('simulator','configs', ...
    'fixtures','e2e_scope_conformance_window.yaml'));

scfg = sixgr.lls6g.config.loadScenarioConfig(fullfile("simulator", "configs", ...
    "scenarios", "lls_causal_access_to_data_wiring_tdd.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scfg, tmp);
cfg.run.strictMode = true;
cfg.channel.model = "TDL-C";
cfg.channel.awgnOnly = false;
cfg.channel.delayProfile = "TDL-C";
cfg.channel.tdlProfile = "TDL-C";
cfg.channel.cdlProfile = "";
cfg.channel.dopplerHz = 70;
cfg.channel.fading.enable = true;
cfg.channel.fading.model = "TDL";
cfg.channel.fading.profile = "TDL-C";
cfg.channel.fading.maxDoppler_Hz = 70;
cfg.traffic.model = "fullBuffer";
cfg.traffic.transport = "UDP";
cfg.traffic.flowDirection = "UL";
cfg.scenario.ue.nUE = 1;
cfg.scenario.nUE = 1;

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmp, ...
    "OnlyE2E", true, ...
    "RunLinkCampaign", false, ...
    "RunDetailedLinkDiagnostics", false, ...
    "RunSystemMMTCProbe", false, ...
    "RunAuxiliaryProbes", false, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", window.duration_s, ...
    "E2EMaxSlots", window.max_slots, ...
    "E2EUECount", 1, ...
    "E2ETrafficModel", "fullbuffer", ...
    "E2EAirModel", "truth", ...
    "E2EStrictValidation", true, ...
    "E2ETruthFastAWGNPath", false, ...
    "E2ETruthCompactPHYIO", true, ...
    "E2ETruthAdaptiveLDPC", true, ...
    "E2ETruthLDPCMaxIterations", 0, ...
    "E2ETruthUseGPU", false, ...
    "E2ETruthMaxSlots", window.max_slots, ...
    "LinkSNR_dB", 30, ...
    "CalibrateSystemBLERFromLink", false, ...
    "UseFastLinkModel", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "GenerateCampaignPlots", false, ...
    "VerifyArtifacts", false, ...
    "Verbose", false);

runFolder = char(string(rep.RunFolder));
layout = sixgr.report.resultLayout(runFolder);
summaryCsv = fullfile(layout.PacketFlowCSVDir, "probe_e2e_summary_truth.csv");
T = readtable(summaryCsv, "VariableNamingRule", "preserve");
assert(rep.Ok,'Metadata qualification requires an accepted physical E2E execution.');
assert(double(T.NumSlots(1))>double(T.AttachSlots(1)) && double(T.OfferedUL_Mbps(1))>0, ...
    'The metadata test must include a real post-attach UL offered population.');
grantTrace=readtable(fullfile(runFolder,char(string(T.SchedulerTraceArtifact(1)))), ...
    'VariableNamingRule','preserve');
assert(~isempty(grantTrace) && any(strcmpi(string(grantTrace.Direction),'UL')), ...
    'An empty or DL-only grant stream does not qualify this UL E2E metadata test.');
manifest = jsondecode(fileread(layout.RunManifestJSON));
approx = readtable(layout.ApproximationsCSV, "VariableNamingRule", "preserve");
reportText = fileread(layout.CampaignReportMD);

assert(ismember("RunScope", string(T.Properties.VariableNames)), ...
    "Truth E2E summary must expose RunScope.");
assert(ismember("ConformanceLevel", string(T.Properties.VariableNames)), ...
    "Truth E2E summary must expose ConformanceLevel.");
assert(ismember("NoProxyTruthContract", string(T.Properties.VariableNames)), ...
    "Truth E2E summary must expose NoProxyTruthContract.");
assert(string(T.RunScope(1)) == "e2e_only", "Truth E2E summary RunScope should be e2e_only.");
assert(string(T.ConformanceLevel(1)) == "system_coupled_truth_replay", ...
    "Truth E2E summary ConformanceLevel should state system-coupled truth replay honestly.");
assert(~logical(T.NoProxyTruthContract(1)), ...
    "Default truth E2E run should not claim the no-proxy truth contract.");

assert(isfield(manifest, "RunScope") && string(manifest.RunScope) == "e2e_only", ...
    "Manifest must record RunScope.");
assert(isfield(manifest, "RunCompletion") && string(manifest.RunCompletion) == "completed_requested_scope", ...
    "Manifest must record RunCompletion.");
assert(isfield(manifest, "ConformanceLevel") && string(manifest.ConformanceLevel) == "system_coupled_truth_replay", ...
    "Manifest must record ConformanceLevel honestly.");
assert(isfield(manifest, "NoProxyTruthContract") && ~logical(manifest.NoProxyTruthContract), ...
    "Manifest must record whether the no-proxy truth contract was enabled.");

assert(~any(string(approx.Component) == "truth_e2e_coupling"), ...
    "Approximations ledger must stop flagging truth E2E coupling once the run is system-coupled.");
assert(contains(reportText, "- Run scope: `e2e_only`"), ...
    "Markdown report must print RunScope.");
assert(contains(reportText, "- Conformance level: `system_coupled_truth_replay`"), ...
    "Markdown report must print ConformanceLevel.");

ok = true;
end
