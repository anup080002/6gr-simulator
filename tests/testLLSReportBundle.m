function localAssertSweepConfidenceBounds(T, valueCol, lowCol, highCol, countCol)
mask = isfinite(double(T.(valueCol)));
assert(any(mask), "Sweep column %s must contain at least one finite value.", valueCol);
vals = double(T.(valueCol));
lo = double(T.(lowCol));
hi = double(T.(highCol));
counts = double(T.(countCol));
assert(all(isfinite(lo(mask)) & isfinite(hi(mask))), ...
    "Sweep confidence bounds for %s must be finite when the point estimate is finite.", valueCol);
assert(all(lo(mask) <= vals(mask) + 1e-9 & hi(mask) >= vals(mask) - 1e-9), ...
    "Sweep confidence bounds for %s must bracket the point estimate.", valueCol);
assert(all(isfinite(counts(mask)) & counts(mask) > 0), ...
    "Sweep trial counts for %s must be positive when the point estimate is finite.", valueCol);
end

function localAssertMetricRowsResolvedOrReasoned(T, metricKey, expectedStats)
mask = string(T.MetricKey) == string(metricKey);
Tm = T(mask, :);
assert(~isempty(Tm), "Metric %s must be emitted in the detail rows.", metricKey);
assert(all(ismember(string(expectedStats), string(Tm.Statistic))), ...
    "Metric %s must emit the expected target/comparison rows.", metricKey);
notes = lower(strjoin(string(Tm.Notes), " | "));
valueText = lower(strjoin(string(Tm.ValueText), " | "));
assert(~contains(notes, "metric not produced by this run"), ...
    "Metric %s must not fall back to the generic missing-metric note.", metricKey);
countsTowardCoverage = ismember("CountsTowardCoverage", string(Tm.Properties.VariableNames)) && ...
    any(logical(Tm.CountsTowardCoverage));
states = unique(string(Tm.Availability));
if countsTowardCoverage
    assert(~contains(notes, "upper_bound") && ~contains(notes, "lower_bound"), ...
        "Metric %s should not use conservative bound labels as if they were measured results.", metricKey);
else
    assert(contains(notes, "not_enough_data") || contains(notes, "no_valid_comparator") || ...
        contains(valueText, "not_enough_data") || contains(valueText, "no_valid_comparator") || ...
        any(ismember(states, ["config_only","disabled","placeholder","not_supported","not_available","not_exercised"])), ...
        "Metric %s must explain unavailable status with an explicit insufficiency/comparator reason.", metricKey);
end
end

function [categoryFiles, metricKeys] = localReadCatalog(path)
txt = string(fileread(path));
categoryFiles = regexp(txt, 'file_name:\s*([^\r\n]+)', 'tokens');
categoryFiles = string(cellfun(@(c) strtrim(c{1}), categoryFiles, 'UniformOutput', false));
metricKeys = regexp(txt, '- \{\s*key:\s*([^,]+),\s*label:', 'tokens');
metricKeys = string(cellfun(@(c) strtrim(c{1}), metricKeys, 'UniformOutput', false));
metricKeys = unique(metricKeys, 'stable');
end

