function ok = testLLSArtifactStatusSeparation()
%TESTLLSARTIFACTSTATUSSEPARATION Written files do not imply completeness.

setup6GRSimToolkit("Verbose", false);
ctx = llsRootGateFixture("pass");
summaryPath = fullfile(ctx.Layout.ReportCSVDir, ...
    "artifact_completeness_summary.csv");
T = table("reports/image/access_delay_cdf.png", 1, false, ...
    "mandatory_artifact_missing", ...
    'VariableNames', {'MissingArtifacts','RequiredArtifactCount', ...
    'ArtifactCompletenessOk','FailureReason'});
sixgr.util.csvWriteTable(summaryPath, T);

verdict = sixgr.truth.evaluateLLSRuntimeTruthContract( ...
    ctx.RunFolder, ctx.ScenarioConfig, ctx.InternalConfig);
status = verdict.ResultStatus;
assert(logical(status.ArtifactsWritten), ...
    "Existing canonical CSVs must report ArtifactsWritten=true.");
assert(~logical(status.ArtifactCompletenessOk) && ~logical(status.ResultOk), ...
    "A missing mandatory artifact must fail completeness without denying file creation.");
assert(contains(string(status.ResultStatusReason), ...
    "required_artifacts_missing_or_incomplete"), ...
    "The completeness failure reason must be distinct from artifacts_not_written.");
ok = true;
end
