function ok = testSystemWaveformPDCCHGrantBinding()
%TESTSYSTEMWAVEFORMPDCCHGRANTBINDING Physical DCI must authorize data.

setup6GRSimToolkit("Verbose", false);

cfg = sixgr.config.defaultConfig();
cfg.run.shortRun = true;
cfg.run.strictMode = true;
cfg.run.useMex = false;
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.fading.enable = false;
cfg.channel.nTxAnt = 1;
cfg.channel.nRxAnt = 1;
cfg.scenario.bs.nTxAnt = 1;
cfg.scenario.bs.nRxAnt = 1;
cfg.scenario.ue.nTxAnt = 1;
cfg.scenario.ue.nRxAnt = 1;
cfg.phy.pdcch.enable = true;
cfg.phy.pdcch.dmrs.enable = true;
cfg.phy.pdcch.blindSearch = false;
cfg.phy.pdcch.listLength = 16;
cfg.phy.pdsch.modulation = "QPSK";
cfg.phy.pdsch.codeRate = 0.3;
cfg.phy.pdsch.numLayers = 1;
cfg.phy.pdsch.nLayers = 1;
cfg.phy.pdsch.dmrs.portSet = 0;
cfg.phy.pdsch.symbolAllocation = [2 12];
cfg.run.controlGating.pdcchRequired = true;
cfg = sixgr.config.normalizeConfig(cfg);
cfg = withCanonicalSchedulerTiming(cfg);

ue = struct( ...
    "RNTI", 41, ...
    "DLBufferBytes", 1200, ...
    "CQI", 7, ...
    "RI", 1, ...
    "HeadOfLineDelay_ms", 1);
scheduler = sixgr.l2.mac.SchedulerRR(cfg, "Direction", "DL");
[grants, ~] = scheduler.schedule(0, ue, struct( ...
    "PRBSet", 0:23, ...
    "SymbolAllocation", [2 12], ...
    "ControlAbsoluteSlot", 0, ...
    "ControlSymbolAllocation", [0 2]));
assert(numel(grants) == 1 && ...
    ~isempty(sixgr.util.structGet(grants(1), "DCI.Bits", [])), ...
    "The fixture requires one finalized bit-exact scheduler DCI.");

replay = sixgr.system.waveform.replayGrant( ...
    cfg, "DL", grants(1), [], 35, "StrictMode", true, ...
    "CompactPHYIO", true, "FastAWGNPath", false);
assert(logical(replay.PDCCHWaveformExecuted), ...
    "Required control did not execute through PDCCH Tx/Rx.");
assert(logical(replay.PDCCHGrantBindingRequired) && ...
    logical(replay.PDCCHGrantBindingOk), ...
    "Physical PDCCH grant binding failed: %s", ...
    replay.PDCCHGrantBindingFailureCode);
assert(strcmp(string(replay.PDCCHGrantBindingStatus), ...
    "bound_physical_waveform"), ...
    "Unexpected PDCCH binding status '%s'.", ...
    replay.PDCCHGrantBindingStatus);
assert(logical(replay.DCICrcPass) && ...
    logical(replay.PDCCHPayloadMatch) && ...
    logical(replay.PDCCHCausalGrantDecodeOk), ...
    "Physical DCI CRC/payload/causal checks did not all pass.");
assert(strlength(string(replay.PDCCHGrantDCIFieldsHash)) == 64 && ...
    string(replay.PDCCHGrantDCIFieldsHash) == ...
    string(replay.PDCCHGrantFieldsHash), ...
    "Decoded DCI semantic fields do not hash to the finalized grant.");
assert(double(replay.PDCCHGrantSearchSpaceId) == ...
    double(grants(1).SearchSpaceID) && ...
    double(replay.PDCCHGrantCORESETId) == ...
    double(grants(1).CORESETID) && ...
    double(replay.PDCCHGrantAggregationLevel) == ...
    double(grants(1).PDCCHAggregationLevel) && ...
    double(replay.PDCCHGrantCandidateIndex) == ...
    double(grants(1).PDCCHCandidateIndex), ...
    "PDCCH resource identity did not round-trip exactly.");
assert(logical(replay.WaveformReplayExecuted), ...
    "Data waveform did not execute after successful physical control.");

corrupt = grants(1);
corrupt.DCI.Bits(1) = uint8(~logical(corrupt.DCI.Bits(1)));
blocked = sixgr.system.waveform.replayGrant( ...
    cfg, "DL", corrupt, [], 35, "StrictMode", true, ...
    "CompactPHYIO", true, "FastAWGNPath", false);
assert(logical(blocked.PDCCHWaveformExecuted) && ...
    ~logical(blocked.PDCCHGrantBindingOk), ...
    "A semantically corrupted DCI must fail physical grant binding.");
assert(~logical(blocked.WaveformReplayExecuted) && ...
    strcmp(string(blocked.PHYDecisionReason), ...
    "pdcch_grant_binding_failed"), ...
    "PDSCH must not execute after a failed decoded-DCI binding.");
assert(contains(string(blocked.PDCCHGrantBindingFailureCode), ...
    "mismatch"), ...
    "The corrupted DCI failure did not disclose its mismatch class.");

ok = true;
end
