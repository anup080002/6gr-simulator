function ok=testRank2SharedAWGNPrecoderContract()
% Scenario-specific guard for the retained 5 MHz/20 dB rank-two failure.
setup6GRSimToolkit('Verbose',false);
source=sixgr.lls6g.config.loadScenarioConfig(fullfile('simulator','configs', ...
    'scenarios','lls_tdd_5mhz_rank2_shared_awgn_20db.yaml'));
sixgr.lls6g.config.validateScenarioConfig(source.toStruct());
cfg=sixgr.lls6g.buildInternalConfig(source,tempname);

% The integrated target must retain its physical control/reference chain.
% A throughput-only/ideal-feedback configuration cannot pass this guard.
requiredBlocks=["phy.pdcch.enable","phy.pucch.enable", ...
    "phy.csi.enable","phy.csi.reportCSI","phy.csi.reportCQI", ...
    "phy.csi.reportPMI","phy.csi.reportRI","phy.csi.reportCRI", ...
    "phy.srs.enable","phy.trs.enable","phy.harq.enable", ...
    "phy.linkAdaptation.innerLoopFlag","phy.linkAdaptation.outerLoopFlag"];
for block=requiredBlocks
    assert(isequal(sixgr.util.structGet(cfg,block,[]),true), ...
        'test:Rank2ScenarioDisabledPhysicalBlock', ...
        'The complete 5 MHz target must keep %s enabled.',block);
end
assert(string(source.get('users.execution_model'))=="slot_coupled_truth" && ...
    string(source.get('scenario.runner_profile'))=="system_level_lls", ...
    'test:Rank2ScenarioExecutionModel', ...
    'The target must execute coupled control/data, not the ideal-feedback throughput runner.');

initial=double(source.get('pdsch.layer_count'));
ceiling=double(source.get('mimo.max_dl_layers'));
assert(initial==1 && ceiling==2 && cfg.phy.pdsch.maxLayers==2, ...
    'test:Rank2ScenarioCapability', ...
    'The fixture must bootstrap at rank one and permit rank two.');
ulInitial=double(source.get('pusch.layer_count'));
ulCeiling=double(source.get('mimo.max_ul_layers'));
assert(ulInitial==1 && ulCeiling==2 && ...
    double(cfg.phy.maxULLayers)==2 && ...
    double(cfg.phy.pusch.maxLayers)==2 && ...
    double(cfg.phy.pusch.maxRankDefault)==2, ...
    'test:Rank2ScenarioULCapability', ...
    'The fixture must bootstrap UL at rank one and expose rank two as a future-grant capability.');
assert(double(cfg.phy.srs.nPorts)==4 && ...
    double(cfg.phy.pusch.NumAntennaPorts)==4 && ...
    isequal(double(cfg.phy.pusch.dmrs.availablePortSet),0:3) && ...
    isequal(double(cfg.phy.pusch.dmrs.portSet),0), ...
    'test:Rank2ScenarioULReferencePorts', ...
    'Rank-two UL adaptation requires four-port SRS and a DM-RS pool while the rank-one bootstrap uses port zero.');

assert(string(source.get('modulation_and_mapping.ul_mcs_table'))=="qam64_table1" && ...
    string(source.get('pusch.mcs_table'))=="qam64_table1" && ...
    string(cfg.phy.pusch.mcsTable)=="qam64_table1" && ...
    string(sixgr.link.resolveConfiguredCQITable(cfg,'UL'))=="table1" && ...
    ~isfield(cfg.phy.pusch,'experimentalMCSTable'), ...
    'test:Rank2ScenarioULMCSAuthority', ...
    'UL CQI and MCS must resolve to the paired TS 38.214 table-1 authority without an experimental table.');
ulBootstrap=sixgr.link.resolveMCSProfile(cfg.phy.pusch.mcsTable,4);
assert(ulBootstrap.Valid && ulBootstrap.Qm==2 && ...
    string(ulBootstrap.Modulation)=="QPSK" && ...
    abs(ulBootstrap.TargetCodeRate-308/1024)<1e-12, ...
    'test:Rank2ScenarioULMCSCodepoint', ...
    'UL bootstrap MCS 4 must equal the TS 38.214 table-1 QPSK 308/1024 codepoint.');
for cqi=1:15
    mapped=sixgr.link.resolveMCSFromCQI(cqi,cfg.phy.pusch.mcsTable, ...
        sixgr.link.resolveConfiguredCQITable(cfg,'UL'));
    direct=sixgr.link.resolveMCSProfile(cfg.phy.pusch.mcsTable,mapped.MCSIndex);
    assert(mapped.Valid && direct.Valid && ...
        mapped.MCSProfile.MCSIndex==direct.MCSIndex && ...
        mapped.MCSProfile.Qm==direct.Qm && ...
        abs(mapped.MCSProfile.TargetCodeRate-direct.TargetCodeRate)<1e-12, ...
        'test:Rank2ScenarioULCQIMCSMapping', ...
        'UL CQI %d did not resolve through one consistent TS 38.214 table-1 MCS authority.',cqi);
end

ulRankPolicy=sixgr.mimo.resolveRankExecutionPolicy(cfg,'UL',2);
ulDCIContext=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,'0_1');
assert(ulRankPolicy.MaxSupportedLayers==2 && ...
    ulRankPolicy.EffectiveRank==2 && ...
    ulDCIContext.Data.LayerCapability==2, ...
    'test:Rank2ScenarioULRuntimeAuthority', ...
    'Scheduler rank policy and received DCI 0_1 context must both preserve the installed UL rank-two capability.');
Hest=repmat(reshape(eye(4),1,1,4,4),[24,2,1,1]);
ulSRS=sixgr.phy.ul.estimateSRSRITPMI(Hest,0.01,cfg);
assert(logical(ulSRS.Valid) && double(ulSRS.RI)==2 && ...
    contains(string(ulSRS.RISource),'post_equalization_mi'), ...
    'test:Rank2ScenarioULMeasuredRank', ...
    'A full-rank four-port SRS observation must select the installed UL rank-two ceiling through measured post-equalization MI.');

normalization=string(sixgr.util.structGet(cfg, ...
    'phy.pdsch.precoding.normalizationConvention',''));
assert(normalization=="unit_frobenius" && ...
    string(sixgr.util.structGet(cfg, ...
    'phy.pusch.precoding.normalizationConvention',''))=="unit_frobenius", ...
    'test:Rank2ScenarioPrecoderNormalization', ...
    'Both directions must preserve the configured fixed total power.');

% PMI 30 is the causal four-port/rank-two selection retained from the
% failed run. It has unit total power and W'*W=I/2; validating it as
% semi-unitary produced the observed Gram residual sqrt(1/2).
pmi=30;
[candidates,~]=sixgr.phy.dl.pmiCodebookCandidates( ...
    cfg,ceiling,4,'Mode','type1_su_mimo');
assert(pmi>=0 && pmi<numel(candidates), ...
    'test:Rank2ScenarioPMIRange','Retained-run PMI 30 is unavailable.');
W=double(candidates(pmi+1).W);
matrixInfo=sixgr.phy.mimo.MatrixContract.validate(W,4,ceiling, ...
    'NormalizationConvention',normalization);
assert(abs(matrixInfo.FrobeniusPower-1)<1e-12 && ...
    norm(W'*W-eye(ceiling)/ceiling,'fro')<1e-12, ...
    'test:Rank2ScenarioPrecoderPower', ...
    'Rank-two PMI must retain unit total power and orthogonal layers.');

% Cross the production resolver boundary that raised the retained error.
% The immutable digest must survive unchanged; runtime normalization stays
% disabled exactly as it is for a frozen scheduler grant.
cfgRank2=cfg;
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.numLayers',ceiling);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.nLayers',ceiling);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.rank',ceiling);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.dmrs.portSet',0:ceiling-1);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.dmrs.scheduledPortSet',0:ceiling-1);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.precoding.matrix',W);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.precodingMatrix',W);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.W',W);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.PMI',pmi);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.normalizePrecodingMatrix',false);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.selectedPrecoderSHA256', ...
    char(matrixInfo.MatrixSHA256));
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.canonicalGrant.enabled',true);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.canonicalGrant.spatialSignature',W);
[cfgRank2,~]=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfgRank2,31,4);
[carrier,~]=sixgr.phy.grid.makeCarrier(cfgRank2);
[~,~,pdsch]=sixgr.phy.grid.allocREsPDSCH(carrier,cfgRank2, ...
    'NumLayers',ceiling);
resolved=sixgr.phy.dl.resolvePDSCHPrecoding(pdsch,cfgRank2);
assert(resolved.AppliedMatrixSHA256==matrixInfo.MatrixSHA256 && ...
    resolved.SelectedMatrixSHA256==matrixInfo.MatrixSHA256 && ...
    norm(double(resolved.MatrixLogicalPorts)-W,'fro')==0, ...
    'test:Rank2ScenarioImmutablePrecoder', ...
    'Production resolution changed or rejected the frozen rank-two PMI.');

fprintf(['RANK2_SHARED_AWGN_PRECODER_CONTRACT_PASS initial=%g maximum=%g ' ...
    'ulInitial=%g ulMaximum=%g ulMCS=%s PMI=%g normalization=%s power=%.16g\n'], ...
    initial,ceiling,ulInitial,cfg.phy.maxULLayers,string(cfg.phy.pusch.mcsTable),pmi,normalization, ...
    matrixInfo.FrobeniusPower);
ok=true;
end
