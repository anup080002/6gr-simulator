function ok=testRank2SharedAWGNPrecoderContract()
% Scenario-specific guard for the retained 5 MHz/20 dB rank-two failure.
setup6GRSimToolkit('Verbose',false);
source=sixgr.lls6g.config.loadScenarioConfig(fullfile('simulator','configs', ...
    'scenarios','lls_tdd_5mhz_rank2_shared_awgn_20db.yaml'));
sixgr.lls6g.config.validateScenarioConfig(source.toStruct());
cfg=sixgr.lls6g.buildInternalConfig(source,tempname);

initial=double(source.get('pdsch.layer_count'));
ceiling=double(source.get('mimo.max_dl_layers'));
assert(initial==1 && ceiling==2 && cfg.phy.pdsch.maxLayers==2, ...
    'test:Rank2ScenarioCapability', ...
    'The fixture must bootstrap at rank one and permit rank two.');
assert(double(source.get('mimo.max_ul_layers'))==1 && ...
    double(cfg.phy.maxULLayers)==1, ...
    'test:Rank2ScenarioULCapability', ...
    'The DL rank fixture must not inherit a four-layer UL ceiling.');

normalization=string(sixgr.util.structGet(cfg, ...
    'phy.pdsch.precoding.normalizationConvention',''));
assert(normalization=="unit_frobenius" && ...
    string(sixgr.util.structGet(cfg, ...
    'phy.pusch.precoding.normalizationConvention',''))=="unit_frobenius", ...
    'test:Rank2ScenarioPrecoderNormalization', ...
    'Both directions must preserve the configured fixed total power.');

% PMI 30 is the causal four-port/rank-two selection retained from the
% failed run. It has unit total power and W'*W=I/2; validating it as
% semi-unitary produced the observed Gram residual sqrt(1/2).
pmi=30;
[candidates,~]=sixgr.phy.dl.pmiCodebookCandidates( ...
    cfg,ceiling,4,'Mode','type1_su_mimo');
assert(pmi>=0 && pmi<numel(candidates), ...
    'test:Rank2ScenarioPMIRange','Retained-run PMI 30 is unavailable.');
W=double(candidates(pmi+1).W);
matrixInfo=sixgr.phy.mimo.MatrixContract.validate(W,4,ceiling, ...
    'NormalizationConvention',normalization);
assert(abs(matrixInfo.FrobeniusPower-1)<1e-12 && ...
    norm(W'*W-eye(ceiling)/ceiling,'fro')<1e-12, ...
    'test:Rank2ScenarioPrecoderPower', ...
    'Rank-two PMI must retain unit total power and orthogonal layers.');

% Cross the production resolver boundary that raised the retained error.
% The immutable digest must survive unchanged; runtime normalization stays
% disabled exactly as it is for a frozen scheduler grant.
cfgRank2=cfg;
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.numLayers',ceiling);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.nLayers',ceiling);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.rank',ceiling);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.dmrs.portSet',0:ceiling-1);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.dmrs.scheduledPortSet',0:ceiling-1);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.precoding.matrix',W);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.precodingMatrix',W);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.W',W);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.PMI',pmi);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.normalizePrecodingMatrix',false);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.pdsch.selectedPrecoderSHA256', ...
    char(matrixInfo.MatrixSHA256));
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.canonicalGrant.enabled',true);
cfgRank2=sixgr.util.structSet(cfgRank2,'phy.canonicalGrant.spatialSignature',W);
[cfgRank2,~]=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfgRank2,31,4);
[carrier,~]=sixgr.phy.grid.makeCarrier(cfgRank2);
[~,~,pdsch]=sixgr.phy.grid.allocREsPDSCH(carrier,cfgRank2, ...
    'NumLayers',ceiling);
resolved=sixgr.phy.dl.resolvePDSCHPrecoding(pdsch,cfgRank2);
assert(resolved.AppliedMatrixSHA256==matrixInfo.MatrixSHA256 && ...
    resolved.SelectedMatrixSHA256==matrixInfo.MatrixSHA256 && ...
    norm(double(resolved.MatrixLogicalPorts)-W,'fro')==0, ...
    'test:Rank2ScenarioImmutablePrecoder', ...
    'Production resolution changed or rejected the frozen rank-two PMI.');

fprintf(['RANK2_SHARED_AWGN_PRECODER_CONTRACT_PASS initial=%g maximum=%g ' ...
    'ulMaximum=%g PMI=%g normalization=%s power=%.16g\n'], ...
    initial,ceiling,cfg.phy.maxULLayers,pmi,normalization, ...
    matrixInfo.FrobeniusPower);
ok=true;
end
