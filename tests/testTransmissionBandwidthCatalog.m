function ok = testTransmissionBandwidthCatalog()
%TESTTRANSMISSIONBANDWIDTHCATALOG Execute all supplied TS 38.104 cells.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

vectors = readtable(localVectorPath("frame_carrier_grid_test_vectors.csv"), ...
    "TextType", "string");
golden = readtable(localVectorPath("expected_carrier_grid_matrix.csv"), ...
    "TextType", "string");
assert(height(vectors) == 71, ...
    "The mandatory carrier-grid vector file must contain all 71 supplied cells.");

n = height(vectors);
testID = string(vectors.TestID);
role = string(vectors.Role);
frequencyRange = string(vectors.FrequencyRange);
centerHz = double(vectors.RepresentativeCenterFrequency_Hz);
bandwidthMHz = double(vectors.ChannelBandwidth_MHz);
scsKHz = double(vectors.CarrierSCS_kHz);
expectedValid = false(n, 1);
resolvedValid = false(n, 1);
expectedNRB = nan(n, 1);
resolvedNRB = nan(n, 1);
nStartGrid = nan(n, 1);
occupiedBandwidthHz = nan(n, 1);
guardLowHz = nan(n, 1);
guardHighHz = nan(n, 1);
errorID = strings(n, 1);
status = repmat("PASS", n, 1);

for i = 1:n
    expectedValid(i) = localTruth(vectors.ExpectedValid(i));
    expectedNRB(i) = double(vectors.ExpectedNRB(i));
    expectedError = string(vectors.ExpectedErrorID(i));
    try
        grid = sixgr.phy.frame.TransmissionBandwidthCatalog.resolve( ...
            "Role", role(i), ...
            "FrequencyRange", frequencyRange(i), ...
            "CenterFrequencyHz", centerHz(i), ...
            "ChannelBandwidthMHz", bandwidthMHz(i), ...
            "SubcarrierSpacingKHz", scsKHz(i));
        resolvedValid(i) = true;
        resolvedNRB(i) = grid.NSizeGrid;
        nStartGrid(i) = grid.NStartGrid;
        occupiedBandwidthHz(i) = grid.OccupiedBandwidthHz;
        guardLowHz(i) = grid.MinimumLowGuardbandHz;
        guardHighHz(i) = grid.MinimumHighGuardbandHz;
        assert(expectedValid(i), ...
            "N/A vector %s unexpectedly resolved as valid.", testID(i));
        assert(grid.NSizeGrid == expectedNRB(i), ...
            "Vector %s resolved N_RB=%g, expected %g.", ...
            testID(i), grid.NSizeGrid, expectedNRB(i));
        assert(abs(grid.MinimumLowGuardbandKHz - ...
            double(vectors.ExpectedMinGuardband_kHz(i))) < 1e-12, ...
            "Vector %s low guardband mismatch.", testID(i));
        assert(abs(grid.MinimumHighGuardbandKHz - ...
            double(vectors.ExpectedMinGuardband_kHz(i))) < 1e-12, ...
            "Vector %s high guardband mismatch.", testID(i));
        assert(string(grid.FrequencyRange) == frequencyRange(i), ...
            "Vector %s frequency-range subtype changed.", testID(i));
    catch ME
        errorID(i) = string(ME.identifier);
        assert(~expectedValid(i), ...
            "Valid vector %s failed with %s: %s", ...
            testID(i), string(ME.identifier), string(ME.message));
        assert(errorID(i) == expectedError, ...
            "Vector %s failed with %s, expected %s.", ...
            testID(i), errorID(i), expectedError);
    end
end

actual = table(testID, role, frequencyRange, centerHz, bandwidthMHz, ...
    scsKHz, expectedValid, resolvedValid, expectedNRB, resolvedNRB, ...
    nStartGrid, occupiedBandwidthHz, guardLowHz, guardHighHz, errorID, status, ...
    'VariableNames', [ ...
    "TestID", "Role", "FrequencyRange", "CenterFrequency_Hz", ...
    "ChannelBandwidth_MHz", "CarrierSCS_kHz", "ExpectedValid", ...
    "ResolvedValid", "ExpectedNRB", "ResolvedNRB", "NStartGrid", ...
    "OccupiedBandwidth_Hz", "GuardbandLow_Hz", "GuardbandHigh_Hz", ...
    "ErrorID", "Status"]);
localAssertGolden(actual, golden);

catalog = sixgr.phy.frame.TransmissionBandwidthCatalog.table();
assert(height(catalog) == height(vectors) && ...
    sum(catalog.Valid) == sum(expectedValid), ...
    "The standard catalog must encode all 71 table cells explicitly, " + ...
    "with exactly the 56 supplied valid cells marked valid.");
assert(all(isnan(catalog.NRB(~catalog.Valid))) && ...
    all(isnan(catalog.MinimumGuardbandKHz(~catalog.Valid))), ...
    "N/A catalog cells must not contain fabricated NRB or guardband values.");

localAssertNRB("FR1", 3, 15, 15);
localAssertNRB("FR1", 35, 30, 92);
localAssertNRB("FR1", 45, 60, 58);
localAssertNRB("FR1", 100, 30, 273);
localAssertNRB("FR2-1", 400, 120, 264);
localAssertNRB("FR2-2", 400, 480, 66);
localAssertNRB("FR2-2", 2000, 960, 148);

assertThrows(@() localResolve("FR2-1", 400, 60), ...
    "sixgr:phy:frame:UnsupportedBandwidthSCSCombination");
assertThrows(@() localResolve("FR2-2", 100, 480), ...
    "sixgr:phy:frame:UnsupportedBandwidthSCSCombination");
range60 = sixgr.phy.frame.FrequencyRangeResolver.resolve(60e9);
assert(string(range60.FrequencyRange) == "FR2-2", ...
    "60 GHz must resolve to FR2-2, never FR3.");
assertThrows(@() sixgr.phy.frame.TransmissionBandwidthCatalog.resolve( ...
    "Role", "gNB", "FrequencyRange", "FR1", ...
    "ChannelBandwidthMHz", 100, "SubcarrierSpacingKHz", 30, ...
    "NSizeGrid", 272), ...
    "sixgr:phy:frame:ConfiguredGridMismatch");
assertThrows(@() sixgr.phy.frame.TransmissionBandwidthCatalog.resolve( ...
    "Role", "gNB", "ChannelBandwidthMHz", 100, ...
    "SubcarrierSpacingKHz", 30), ...
    "sixgr:phy:frame:MissingFrequencyRange");

standardWithBWP = sixgr.phy.frame.CarrierGridConfig.resolve( ...
    "Role", "gNB", "FrequencyRange", "FR1", ...
    "ChannelBandwidthMHz", 100, "SubcarrierSpacingKHz", 30, ...
    "NStartBWP", 10, "NSizeBWP", 100);
assert(standardWithBWP.NSizeGrid == 273 && ...
    standardWithBWP.ActiveBWP.NStartBWP == 10 && ...
    standardWithBWP.ActiveBWP.NSizeBWP == 100, ...
    "A BWP must remain an explicit subset of the transmission grid.");
mixedSCSBWP = sixgr.phy.frame.CarrierGridConfig.resolve( ...
    "Role", "gNB", "FrequencyRange", "FR1", ...
    "ChannelBandwidthMHz", 100, "SubcarrierSpacingKHz", 30, ...
    "NStartBWP", 24, "NSizeBWP", 100, ...
    "BWPSubcarrierSpacingKHz", 60);
assert(mixedSCSBWP.ActiveBWP.UpperEdgeOffsetHz == 89.28e6 && ...
    mixedSCSBWP.ActiveBWP.CarrierUpperEdgeOffsetHz == 98.28e6, ...
    "Mixed-SCS containment must compare exact Point-A frequency edges.");
assertThrows(@() sixgr.phy.frame.CarrierGridConfig.resolve( ...
    "Role", "gNB", "FrequencyRange", "FR1", ...
    "ChannelBandwidthMHz", 100, "SubcarrierSpacingKHz", 30, ...
    "NStartBWP", 150, "NSizeBWP", 100, ...
    "BWPSubcarrierSpacingKHz", 60), ...
    "sixgr:phy:frame:BWPOutsideCarrierGrid");
assertThrows(@() sixgr.phy.frame.CarrierGridConfig.resolve( ...
    "Role", "gNB", "FrequencyRange", "FR1", ...
    "ChannelBandwidthMHz", 100, "SubcarrierSpacingKHz", 30, ...
    "NStartBWP", 250, "NSizeBWP", 30), ...
    "sixgr:phy:frame:BWPOutsideCarrierGrid");
assertThrows(@() sixgr.phy.frame.CarrierGridConfig.custom( ...
    "ResearchMode", false, "CenterFrequencyHz", 12e9, ...
    "ChannelBandwidthMHz", 100, "SubcarrierSpacingKHz", 75, ...
    "NSizeGrid", 100), ...
    "sixgr:phy:frame:CustomCarrierRequiresOptIn");
custom = sixgr.phy.frame.CarrierGridConfig.custom( ...
    "ResearchMode", true, "CenterFrequencyHz", 12e9, ...
    "ChannelBandwidthMHz", 100, "SubcarrierSpacingKHz", 75, ...
    "NSizeGrid", 100);
assert(~custom.StandardNR && string(custom.Kind) == ...
    "explicit_custom_research_grid" && isnan(custom.MinimumLowGuardbandHz), ...
    "Custom research grids must remain separate and explicitly non-standard.");

ok = true;
end

function grid = localResolve(frequencyRange, bandwidthMHz, scsKHz)
grid = sixgr.phy.frame.TransmissionBandwidthCatalog.resolve( ...
    "Role", "gNB", ...
    "FrequencyRange", frequencyRange, ...
    "ChannelBandwidthMHz", bandwidthMHz, ...
    "SubcarrierSpacingKHz", scsKHz);
end

function localAssertNRB(frequencyRange, bandwidthMHz, scsKHz, expectedNRB)
grid = localResolve(frequencyRange, bandwidthMHz, scsKHz);
assert(grid.NSizeGrid == expectedNRB, ...
    "%s / %g MHz / %g kHz resolved %g RB, expected %g.", ...
    frequencyRange, bandwidthMHz, scsKHz, grid.NSizeGrid, expectedNRB);
end

function localAssertGolden(actual, golden)
assert(height(actual) == height(golden), ...
    "Resolved carrier output row count differs from the supplied golden output.");
assert(isequal(string(actual.Properties.VariableNames), ...
    string(golden.Properties.VariableNames)), ...
    "Resolved carrier output schema differs from the supplied golden output.");
for i = 1:width(actual)
    name = actual.Properties.VariableNames{i};
    a = actual.(name);
    g = golden.(name);
    if isnumeric(a) || islogical(a)
        if islogical(a)
            g = arrayfun(@localTruth, g);
            assert(isequal(a, logical(g)), ...
                "Golden mismatch in logical column %s.", name);
        else
            g = double(g);
            assert(all((isnan(a) & isnan(g)) | abs(a - g) < 1e-9), ...
                "Golden mismatch in numeric column %s.", name);
        end
    else
        assert(isequal(localText(a), localText(g)), ...
            "Golden mismatch in text column %s.", name);
    end
end

function value = localText(value)
value = string(value);
value(ismissing(value)) = "";
end
end

function tf = localTruth(value)
if islogical(value)
    tf = logical(value);
elseif isnumeric(value)
    tf = logical(value ~= 0);
else
    tf = any(strcmpi(strtrim(string(value)), ["true", "1", "yes"]));
end
end

function assertThrows(fn, expectedID)
try
    fn();
catch ME
    assert(strcmp(ME.identifier, expectedID), ...
        "Expected error %s, received %s.", expectedID, ME.identifier);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.", expectedID);
end

function path = localVectorPath(name)
testDirectory = fileparts(mfilename("fullpath"));
path = fullfile(testDirectory, "vectors", "frame_grid", name);
assert(isfile(path), "Mandatory frame/grid vector is missing: %s", path);
end
