function ok = testLLSOperatingPointAuthority()
%TESTLLSOPERATINGPOINTAUTHORITY Requested CQI and actual grant operating point must stay disambiguated.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
cfg.run.numFrames = 1;
cfg.channel.snr_dB = 10;
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.run.noiseOperatingMode = "receiver_noise_figure_thermal_noise";
cfg.run.interferenceExecutionMode = "none";
cfg.phy.pdsch.dmrs.DMRSTypeAPosition = 3;
cfg.phy.pdsch.dmrs.typeAPosition = 3;
cfg.phy.pusch.dmrs.DMRSTypeAPosition = 3;
cfg.phy.pusch.dmrs.typeAPosition = 3;
cfg.phy.dmrs.typeAPosition = 3;

multiUser = struct("Enabled", true, "NumUsers", 1, "RNTIStart", 320, "ExecutionModel", "slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize(cfg, fullfile(tmp, "runtime"), multiUser, struct(), 1);
state.CurrentServingIdx(1) = 1;
state.CurrentServingMetric_dBm(1) = -70;
state.CurrentSlot = 1;
state.CurrentFrame = 1;
state.CurrentSNR_dB = 10;
state.LargeScaleState.BeamIndex(1,1) = 1;
state.LargeScaleState.BeamGain_dB(1,1) = 0;
state.LargeScaleState.RxPower_dBm(1,1) = -70;
state.LargeScaleState.BasePathloss_dB(1,1) = 100;
state.LargeScaleState.Pathloss_dB(1,1) = 100;
state.LargeScaleState.Shadow_dB(1,1) = 0;
state.LargeScaleState.O2I_dB(1,1) = 0;
[cfgDL, state] = sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg, state, 1, "DL");
[cfgUL, state] = sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg, state, 1, "UL");

grant = struct( ...
    "UEIndex", 1, ...
    "RNTI", 320, ...
    "ServingCell", 1, ...
    "CQIUsed", 15, ...
    "RIUsed", 1, ...
    "PMI", 0, ...
    "CRI", 0, ...
    "MCS", 10, ...
    "MCSIndex", 10, ...
    "Modulation", "16QAM", ...
    "TargetCodeRate", 0.33203125, ...
    "MCSTable", "qam64_table1", ...
    "CQITable", "table1", ...
    "AMCMode", "cqi_driven", ...
    "MCSValueStatus", "unit_test_exact_frozen_grant_status", ...
    "GrantReason", "operating_point_authority_unit_test", ...
    "Frame", 1, ...
    "Slot", 1, ...
    "HARQ", struct());
grantDL = localFinalizeSchedulerTruthGrant(cfgDL, grant, "DL", 10);
grantUL = localFinalizeSchedulerTruthGrant(cfgUL, grant, "UL", 10);

dl = sixgr.link.runDLPDSCHThroughput(cfgDL, ...
    "NumFrames", 1, ...
    "SNR_dB", 10, ...
    "GrantSnapshot", grantDL, ...
    "InterferenceBundle", struct([]));
ul = sixgr.link.runULPUSCHThroughput(cfgUL, ...
    "NumFrames", 1, ...
    "SNR_dB", 10, ...
    "GrantSnapshot", grantUL, ...
    "InterferenceBundle", struct([]));

localAssertOperatingPointAuthority(dl.TrialTable, "DL");
localAssertOperatingPointAuthority(ul.TrialTable, "UL");

staleCQIGrant = grant;
staleCQIGrant.CQIUsed = 1;
staleCQIGrant.MCS = 10;
staleCQIGrant.MCSIndex = 10;
staleCQIGrant.GrantReason = "stale_scheduler_cqi_must_not_override_receiver_measurement";
staleCQIGrantDL = localFinalizeSchedulerTruthGrant(cfgDL, staleCQIGrant, "DL", 35);
staleCQIGrantUL = localFinalizeSchedulerTruthGrant(cfgUL, staleCQIGrant, "UL", 35);
dlStaleCQI = sixgr.link.runDLPDSCHThroughput(cfgDL, ...
    "NumFrames", 1, ...
    "SNR_dB", 35, ...
    "GrantSnapshot", staleCQIGrantDL, ...
    "InterferenceBundle", struct([]));
ulStaleCQI = sixgr.link.runULPUSCHThroughput(cfgUL, ...
    "NumFrames", 1, ...
    "SNR_dB", 35, ...
    "GrantSnapshot", staleCQIGrantUL, ...
    "InterferenceBundle", struct([]));
localAssertReceiverCQIPrecedesStaleGrant(dlStaleCQI.TrialTable, "DL");
localAssertReceiverCQIPrecedesStaleGrant(ulStaleCQI.TrialTable, "UL");

lineageGrant = staleCQIGrant;
lineageGrant.CQIUsed = 7;
lineageGrant.RawCQIDerivedMCS = 11;
lineageGrant.CQIProvenance = "runtime_reported_cqi";
lineageGrant.MCSSelectionSource = "runtime_link_adaptation_decision";
lineageGrant.GrantReason = "authoritative_scheduler_cqi_lineage";
lineageGrant = localFinalizeSchedulerTruthGrant(cfgDL, lineageGrant, "DL", 24);
dlLineageCQI = sixgr.link.runDLPDSCHThroughput(cfgDL, ...
    "NumFrames", 1, ...
    "SNR_dB", 24, ...
    "GrantSnapshot", lineageGrant, ...
    "InterferenceBundle", struct([]));
localAssertSchedulerCQILineagePrecedesReceiverDiagnostics(dlLineageCQI.TrialTable);
ok = true;
end

function grant = localFinalizeSchedulerTruthGrant(cfg, seedGrant, direction, snr_dB)
direction = upper(string(direction));
grant = seedGrant;
grant.Direction = char(direction);
nPRB = max(1, round(double(sixgr.util.structGet(cfg, "frequency.n_size_grid", 24))));
grant.PRBSet = 0:(nPRB - 1);
root = "phy.pdsch";
if direction == "UL"
    root = "phy.pusch";
end
grant.SymbolAllocation = double(sixgr.util.structGet(cfg, ...
    root + ".SymbolAllocation", [0 14]));
grant.NumLayers = double(sixgr.util.structGet(cfg, root + ".nLayers", 1));
grant.Layers = grant.NumLayers;
grant.DMRSPortSet = 0:(grant.NumLayers - 1);
[grant.PTRSEnabled, grant.PTRSPortSet, grant.PTRSPortSetSource] = ...
    sixgr.phy.grant.resolveScheduledPTRSPortSet( ...
    cfg, direction, grant.DMRSPortSet, grant);
if direction == "DL"
    grant.MCSContext = sixgr.util.structGet(cfg, "phy.pdsch.mcsContext", struct());
end
scheduler = sixgr.l2.mac.SchedulerPF(cfg, "Direction", direction);
grant = scheduler.finalizeExactPHYFeasibility(grant);
assert(logical(grant.ExactPHYFeasible) && double(grant.TBSBits) > 0, ...
    "%s operating-point fixture requires an exactly feasible production grant: %s", ...
    direction, string(sixgr.util.structGet(grant, ...
    "ExactPHYInfeasibilityReason", "unknown")));
grant.DCI = struct("BitExactPDCCHPayload", true);
bindingHash = "operating-point-authority-" + lower(direction) + "-binding";
grant.ControlDecodeOk = true;
grant.DCICrcPass = true;
grant.PDCCHPayloadMatch = true;
grant.PDCCHGrantBindingRequired = true;
grant.PDCCHGrantBindingOk = true;
grant.PDCCHGrantBindingStatus = "matched";
grant.PDCCHGrantDCIId = "operating-point-authority-" + lower(direction) + "-dci";
grant.PDCCHGrantDCIFieldsHash = char(bindingHash);
grant.PDCCHGrantFieldsHash = char(bindingHash);
grant.PHYGrant = sixgr.phy.grant.freezePHYGrant(cfg, direction, grant, ...
    "SNR_dB", snr_dB, "Frame", grant.Frame, "Slot", grant.Slot);
end

function localAssertOperatingPointAuthority(T, direction)
assert(istable(T) && height(T) == 1, ...
    "Expected a single %s row for operating-point authority validation.", direction);
requiredVars = {'LinkAdaptationMode','ConfiguredLinkAdaptationMode','ActualMCSSelectionMode','ConfiguredMCSSelectionPolicy', ...
    'SchedulerGrantMCSSelectionMode','RequestedOperatingPointSource', ...
    'WidebandCQI','CQIDerivedMCS','CQIDerivedModulation','CQIDerivedTargetCodeRate','MCS','Modulation','TargetCodeRate', ...
    'MCSAuthority','ModulationAuthority','MCSValueStatus','GrantOperatingPointSource','AppliedOperatingPointSource'};
assert(all(ismember(requiredVars, T.Properties.VariableNames)), ...
    "Raw %s trial row must expose requested/derived/actual operating-point lineage.", direction);
assert(strlength(string(T.LinkAdaptationMode(1))) > 0, ...
    "Raw %s trial row must preserve a non-empty link-adaptation intent label.", direction);
assert(strlength(string(T.ConfiguredLinkAdaptationMode(1))) > 0 && ...
    strcmpi(char(string(T.ConfiguredMCSSelectionPolicy(1))), "cqi_driven") && ...
    strcmpi(char(string(T.RequestedOperatingPointSource(1))), "cqi_link_adaptation"), ...
    "Raw %s trial row must preserve the configured AMC policy separately from the applied runtime source.", direction);
assert(strcmpi(char(string(T.ActualMCSSelectionMode(1))), "scheduler_grant"), ...
    "Raw %s trial row must disclose that the transmitted operating point came from the applied scheduler grant.", direction);
assert(strcmpi(char(string(T.SchedulerGrantMCSSelectionMode(1))), "cqi_driven"), ...
    "Raw %s trial row must preserve the scheduler-grant AMC mode separately from the grant-source authority token.", direction);
assert(~strcmpi(char(string(T.ActualMCSSelectionMode(1))), char(string(T.ConfiguredMCSSelectionPolicy(1)))), ...
    "Raw %s trial row must not relabel configured AMC policy as the actual runtime selection mode.", direction);
assert(strcmpi(char(string(T.MCSAuthority(1))), "scheduler_grant") && ...
    strcmpi(char(string(T.ModulationAuthority(1))), "scheduler_grant") && ...
    strcmpi(char(string(T.GrantOperatingPointSource(1))), "scheduler_grant") && ...
    strcmpi(char(string(T.AppliedOperatingPointSource(1))), "scheduler_grant"), ...
    "Raw %s trial row must not relabel CQI-derived estimates as the applied operating point.", direction);
assert(strcmp(string(T.MCSValueStatus(1)), "unit_test_exact_frozen_grant_status"), ...
    "Raw %s trial row must preserve the exact frozen-grant MCS value-status token.", direction);
assert(isfinite(double(T.WidebandCQI(1))) && isfinite(double(T.CQIDerivedMCS(1))) && strlength(string(T.CQIDerivedModulation(1))) > 0, ...
    "Raw %s trial row must preserve the CQI-derived recommendation separately.", direction);
assert(double(T.MCS(1)) == 10 && strcmpi(char(string(T.Modulation(1))), "16QAM"), ...
    "Raw %s trial row must preserve the actual grant-applied operating point separately from CQI-derived recommendations.", direction);
assert(double(T.MCS(1)) == 10 && strcmpi(char(string(T.MCSAuthority(1))), "scheduler_grant") && ...
    strcmpi(char(string(T.ModulationAuthority(1))), "scheduler_grant"), ...
    "Raw %s trial row must preserve the actual grant-applied operating point even when the CQI-derived recommendation may coincide.", direction);
end

function localAssertReceiverCQIPrecedesStaleGrant(T, direction)
assert(istable(T) && height(T) == 1, ...
    "Expected a single %s row for stale-grant CQI precedence validation.", direction);
requiredVars = {'WidebandCQI','CQISource','MeasuredTrialSINR_dB','MeasuredTrialSINRSource','MCS','MCSAuthority'};
assert(all(ismember(requiredVars, T.Properties.VariableNames)), ...
    "Raw %s trial row must expose measured CQI/SINR provenance and applied grant authority.", direction);
assert(isfinite(double(T.MeasuredTrialSINR_dB(1))), ...
    "Regression setup requires a finite measured %s post-equalization SINR.", direction);
assert(isfinite(double(T.WidebandCQI(1))) && double(T.WidebandCQI(1)) > 1, ...
    "Measured receiver CQI must replace stale scheduler CQIUsed=1 when current %s receiver evidence is available.", direction);
assert(~contains(lower(string(T.CQISource(1))), "scheduler_grant_cqi_used_no_current_receiver_cqi"), ...
    "%s CQISource must not claim grant-CQI fallback when receiver CQI evidence exists.", direction);
assert(double(T.MCS(1)) == 10 && strcmpi(char(string(T.MCSAuthority(1))), "scheduler_grant"), ...
    "The applied %s MCS must still remain the finalized scheduler grant while CQI is reported as receiver evidence.", direction);
end

function localAssertSchedulerCQILineagePrecedesReceiverDiagnostics(T)
assert(istable(T) && height(T) == 1, ...
    "Expected a single DL row for scheduler-CQI lineage validation.");
requiredVars = {'WidebandCQI','CQISource','CQIDerivedMCS','MCS','MCSAuthority'};
assert(all(ismember(requiredVars, T.Properties.VariableNames)), ...
    "Raw DL trial row must expose CQI lineage fields.");
assert(double(T.WidebandCQI(1)) == 7 && double(T.CQIDerivedMCS(1)) == 11, ...
    "Authoritative scheduler CQI lineage must be preserved in DL trial CQI/MCS fields.");
assert(contains(lower(string(T.CQISource(1))), "scheduler_grant"), ...
    "Scheduler-lineage CQISource must disclose scheduler grant authority.");
assert(double(T.MCS(1)) == 10 && strcmpi(char(string(T.MCSAuthority(1))), "scheduler_grant"), ...
    "Applied DL MCS must remain the finalized scheduler grant while CQI lineage reports the grant-driving CQI.");
end
