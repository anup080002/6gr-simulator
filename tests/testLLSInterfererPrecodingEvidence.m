function ok = testLLSInterfererPrecodingEvidence()
%TESTLLSINTERFERERPRECODINGEVIDENCE Verify full-truth interference exports interferer beam/precoder provenance.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml"));
cfgVictim = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
cfgVictim.run.numFrames = 1;
cfgVictim.channel.snr_dB = 10;
cfgVictim.channel.model = "AWGN";
cfgVictim.channel.awgnOnly = true;
cfgVictim.run.noiseOperatingMode = "receiver_noise_figure_thermal_noise";
cfgVictim.run.interferenceExecutionMode = "full_per_link_channel_waveform_sum";

cfgInterferer = cfgVictim;
cfgInterferer.run.seed = double(sixgr.util.structGet(cfgVictim, "run.seed", 1)) + 17;
cfgInterferer = sixgr.util.structSet(cfgInterferer, "phy.pdsch.numLayers", 2);
cfgInterferer = sixgr.util.structSet(cfgInterferer, "phy.pdsch.nLayers", 2);
cfgInterferer = sixgr.util.structSet(cfgInterferer, "phy.pdsch.numPorts", 2);
cfgInterferer = sixgr.util.structSet(cfgInterferer, "phy.pdsch.nPorts", 2);
cfgInterferer = sixgr.util.structSet(cfgInterferer, "phy.nTxAnt", 2);
cfgInterferer = sixgr.util.structSet(cfgInterferer, "phy.pdsch.PMI", 0);
cfgInterferer = sixgr.util.structSet(cfgInterferer, "phy.csi.pmiCodebookMode", "type1_su_mimo");

[previewTx, previewInfo] = sixgr.phy.dl.PDSCH_Tx(cfgVictim, "CompactOutput", true);
contribution = complex(ones(size(previewTx.Waveform)), zeros(size(previewTx.Waveform))) .* 1e-6;
contributionFs = double(sixgr.util.structGet(previewInfo, "OFDM.SampleRate", 30.72e6));

W = (1 / sqrt(2)) * [1 1; 1 -1];
grant = struct( ...
    "UEIndex", 2, ...
    "RNTI", 402, ...
    "ServingCell", 2, ...
    "Frame", 1, ...
    "Slot", 1, ...
    "PRBSet", 0:9, ...
    "SymbolAllocation", [0 14], ...
    "PrecodingMatrix", reshape(W.', [2, 2, 1]), ...
    "PrecoderSource", "unit_test_explicit_matrix", ...
    "PrecodingMode", "explicit-wideband", ...
    "PrecodingApplicationStage", "nrPDSCHPrecode_before_RE_mapping", ...
    "PrecodingActive", true, ...
    "ExplicitBeamWeightsApplied", true, ...
    "TransformPrecodingApplied", false, ...
    "BeamformingApplied", true, ...
    "AppliedBeamIndexSet", "1|2", ...
    "AppliedPrecoderPMI", 0, ...
    "AppliedPrecoderPMIType", "type1", ...
    "AppliedPrecoderCodebookMode", "type1_su_mimo", ...
    "PrecodingNumPorts", 2, ...
    "PrecodingNumLayers", 2, ...
    "PrecodingMatrixRows", 2, ...
    "PrecodingMatrixCols", 2);

bundle = struct( ...
    "Cfg", cfgInterferer, ...
    "GrantSnapshot", grant, ...
    "TransportBlockBits", [], ...
    "RV", [], ...
    "VictimUEIndex", 1, ...
    "InterfererUEIndex", 2, ...
    "ServingCell", 2, ...
    "VictimRxPower_dBm", -65, ...
    "VictimRSRP_dBm", -68, ...
    "BasePathloss_dB", 100, ...
    "Pathloss_dB", 100, ...
    "ShadowFading_dB", 0, ...
    "O2I_dB", 0, ...
    "BeamIndex", 1, ...
    "BeamGain_dB", 0, ...
    "InterferenceMode", "full_per_link_channel_waveform_sum", ...
    "SourceId", "unit_test_interferer_precoder", ...
    "SharedSlotContributionWaveform", contribution, ...
    "ContributionSampleRate_Hz", contributionFs, ...
    "ChannelObjectSource", "unit_test_shared_slot_channel", ...
    "ChannelObjectClass", "unit_test_matrix_channel", ...
    "ChannelArrayHandlingStatus", "shared_slot_receiver_contribution", ...
    "ChannelArrayHandlingBlocker", "", ...
    "ChannelGeometryCouplingLevel", "unit_test_exact_samples", ...
    "ChannelUsesSameRuntimeAntennaAssumptions", true, ...
    "Frame", 1, ...
    "Slot", 1, ...
    "Seed", 31337);

res = sixgr.link.runDLPDSCHThroughput(cfgVictim, ...
    "NumFrames", 1, ...
    "SNR_dB", 10, ...
    "InterferenceBundle", bundle);

T = res.TrialTable;
assert(istable(T) && height(T) == 1, ...
    "Expected one DL raw trial row for interferer-precoding provenance.");
required = { ...
    'InterferenceContributorCount','FullInterfererChannelTruthUsed','InterfererBeamformingAppliedCount', ...
    'InterfererExplicitBeamWeightCount','InterfererTransformPrecodingCount', ...
    'InterfererPrecoderSourceSet','InterfererPrecodingModeSet','InterfererBeamIndexSetSummary'};
assert(all(ismember(required, T.Properties.VariableNames)), ...
    "DL raw trial table must expose interferer precoding provenance fields.");
assert(double(T.InterferenceContributorCount(1)) >= 1, ...
    "Interferer provenance test must observe at least one overlapping interferer.");
assert(logical(T.FullInterfererChannelTruthUsed(1)), ...
    "Interferer provenance test must preserve the full per-link truth flag.");
assert(double(T.InterfererBeamformingAppliedCount(1)) >= 1, ...
    "Interferer provenance test must count beamformed interferers.");
assert(double(T.InterfererExplicitBeamWeightCount(1)) >= 1, ...
    "Interferer provenance test must count explicit-beam-weight interferers.");
assert(contains(char(string(T.InterfererPrecoderSourceSet(1))), "unit_test_explicit_matrix"), ...
    "Interferer provenance test must expose the interferer precoder source.");
assert(contains(char(string(T.InterfererPrecodingModeSet(1))), "explicit-wideband"), ...
    "Interferer provenance test must expose the interferer precoding mode.");
assert(contains(char(string(T.InterfererBeamIndexSetSummary(1))), "1|2"), ...
    "Interferer provenance test must expose the interferer beam index set.");
noiseSource = string(T.NoiseVarianceSource(1));
assert(~contains(noiseSource, "plus_full_waveform_interference_power"), ...
    "Shared-slot interference must not be folded into InjectedNoiseVariance as a second scalar noise term.");
assert(contains(noiseSource, "excluding_interference_modeled_by_shared_slot_covariance"), ...
    "Noise variance provenance must disclose that shared-slot interference is modeled by covariance, not scalar AWGN.");

ok = true;
end
