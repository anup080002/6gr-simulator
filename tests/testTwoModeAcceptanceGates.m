function ok = testTwoModeAcceptanceGates()
%TESTTWOMODEACCEPTANCEGATES Final acceptance must distinguish fixed sweep vs geometry.

setup6GRSimToolkit("Verbose", false);

assert(usejava("jvm"), ...
    "testTwoModeAcceptanceGates requires MATLAB JVM plotting for required image-backed acceptance gates.");

tmp = tempname;
mkdir(tmp);
cleanupObj = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

localExerciseFixedSweepAcceptance(fullfile(tmp, "fixed"));
localExerciseGeometryAcceptance(fullfile(tmp, "geometry"));

ok = true;
end

function localExerciseFixedSweepAcceptance(runFolder)
mkdir(runFolder);
snrGrid = [0 8 16];
trialsPerPoint = 20;
cfg = struct();
localWriteFixedAuditPrereqs(runFolder, snrGrid, trialsPerPoint);
localWriteFixedAcceptanceFixture(runFolder, snrGrid, trialsPerPoint);
sixgr.analytics.evaluatePublicationReadinessGates(cfg, runFolder);

gatePath = fullfile(runFolder, "reports", "csv", "two_mode_acceptance_gates.csv");
assert(exist(gatePath, "file") == 2, ...
    "Fixed sweep acceptance must write reports/csv/two_mode_acceptance_gates.csv.");
gateT = readtable(gatePath, "VariableNamingRule", "preserve", "TextType", "string");
assert(localGateStatus(gateT, "RunClassFixedSNRSweep") == "PASS", ...
    "Fixed sweep runs must classify as fixed_snr_sweep_lls.");
assert(localGateStatus(gateT, "FixedSNRSweepAudit") == "PASS", ...
    "A complete fixed sweep fixture must pass the fixed sweep audit acceptance row.");
assert(localGateStatus(gateT, "ULCurveNonEmpty") == "PASS", ...
    "A complete fixed sweep fixture must pass the UL curve acceptance row.");

ulCurvePath = fullfile(runFolder, "reports", "csv", "ul_fixed_snr_bler_curve.csv");
ulCurveT = readtable(ulCurvePath, "VariableNamingRule", "preserve", "TextType", "string");
sixgr.util.csvWriteTable(ulCurvePath, ulCurveT([],:));
sixgr.analytics.evaluatePublicationReadinessGates(cfg, runFolder);
gateT = readtable(gatePath, "VariableNamingRule", "preserve", "TextType", "string");
assert(localGateStatus(gateT, "ULCurveNonEmpty") == "FAIL", ...
    "Fixed sweep acceptance must fail when the UL BLER curve is empty.");
end

function localExerciseGeometryAcceptance(runFolder)
mkdir(runFolder);
cfg = localGeometryCfg();

traceT = localRuntimeTraceTable(cfg);
sixgr.analytics.writeAnalysisTable(fullfile(runFolder, "reports", "csv", "live_rsrp_serving_trace.csv"), traceT);
sixgr.util.csvWriteTable(fullfile(runFolder, "air_interface", "csv", "dl_pdsch_trials.csv"), localTrialTable("DL"));
sixgr.util.csvWriteTable(fullfile(runFolder, "air_interface", "csv", "ul_pusch_trials.csv"), localTrialTable("UL"));
localWriteGeometryAuditPrereqs(runFolder, cfg);

sixgr.analytics.buildPhase7ReadinessArtifacts(cfg, runFolder);
sixgr.validation.auditGeometryScenarioRun(runFolder, "Strict", false, "WriteOutputs", true);
sixgr.visual.plotGeometryScenarioEvidence(runFolder);
sixgr.validation.auditRunArtifacts(runFolder, "Strict", false, "WriteOutputs", true);
sixgr.analytics.evaluatePublicationReadinessGates(cfg, runFolder);

gatePath = fullfile(runFolder, "reports", "csv", "two_mode_acceptance_gates.csv");
gateT = readtable(gatePath, "VariableNamingRule", "preserve", "TextType", "string");
assert(localGateStatus(gateT, "RunClassGeometry") == "PASS", ...
    "Geometry runs must classify as ue_placement_geometry_lls.");
assert(localGateStatus(gateT, "TrajectoryNonEmpty") == "PASS", ...
    "A complete geometry fixture must pass the trajectory acceptance row.");
assert(localGateStatus(gateT, "DopplerReconciliationPass") == "PASS", ...
    "A complete geometry fixture must pass the Doppler reconciliation acceptance row.");

sixgr.analytics.buildPhase7ReadinessArtifacts(cfg, runFolder);
grade = jsondecode(fileread(fullfile(runFolder, "reports", "final", "final_grade.json")));
assert(isfield(grade, "RunClass") && string(grade.RunClass) == "ue_placement_geometry_lls", ...
    "The final grade JSON must record the geometry run class.");
assert(isfield(grade, "PublicationReadinessOk") && ~logical(grade.PublicationReadinessOk), ...
    "Geometry-only runs must not be marked publication-ready for fixed-link PHY curves.");

trajPath = fullfile(runFolder, "geometry", "csv", "trajectory_geometry.csv");
trajT = readtable(trajPath, "VariableNamingRule", "preserve", "TextType", "string");
sixgr.util.csvWriteTable(trajPath, trajT([],:));
sixgr.analytics.evaluatePublicationReadinessGates(cfg, runFolder);
gateT = readtable(gatePath, "VariableNamingRule", "preserve", "TextType", "string");
assert(localGateStatus(gateT, "TrajectoryNonEmpty") == "FAIL", ...
    "Geometry acceptance must fail when trajectory_geometry.csv is empty.");
end

function status = localGateStatus(T, gateName)
gateNames = strtrim(string(T.GateName));
target = strtrim(string(gateName));
mask = strcmpi(gateNames, target);
assert(any(mask), "Missing gate row: %s. Available rows: %s", gateName, strjoin(unique(gateNames), ", "));
status = strtrim(string(T.Status(find(mask, 1, "first"))));
end

