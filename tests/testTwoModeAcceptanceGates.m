function T = localRuntimeTraceTable(cfg)
slotDuration_s = double(cfg.frame_timing.slot_duration_ms) / 1e3;
speed_mps = double(cfg.mobility.ue_speed_kmh) / 3.6;
fcHz = double(cfg.frequency.center_frequency_hz);
c = 299792458;
sitePos = [0 0 25; 500 0 25];
basePathloss = [101, 103];
shadow = [2.0, 3.0];
o2i = [0, 0];
rows = repmat(struct( ...
    "Slot", NaN, "Time_s", NaN, "UEID", NaN, "CellID", NaN, "ServingCell", NaN, ...
    "X_m", NaN, "Y_m", NaN, "Z_m", NaN, "Speed_kmh", NaN, "Speed_mps", NaN, ...
    "Heading_deg", NaN, "Heading_rad", NaN, ...
    "Distance2D_m", NaN, "Distance3D_m", NaN, "PropagationDelay_s", NaN, ...
    "RadialVelocity_mps", NaN, "ExpectedDopplerHz", NaN, "AppliedDopplerHz", NaN, "SignedDoppler_Hz", NaN, ...
    "BasePathloss_dB", NaN, "Pathloss_dB", NaN, "ShadowFading_dB", NaN, "O2I_dB", NaN, ...
    "LOSFlag", false, "LOSState", "", "PathlossModelSource", "", "PathlossComplianceStatus", "", ...
    "LOSProbabilitySource", "", "LOSComplianceStatus", "", "Status", ""), 8, 1);

rowIdx = 1;
for ue = 1:2
    for slot = 1:4
        t = double(slot - 1) * slotDuration_s;
        if ue == 1
            pos = [120 + speed_mps * t, 25, 1.5];
            headingDeg = 0;
        else
            pos = [380 - speed_mps * t, -25, 1.5];
            headingDeg = 180;
        end
        site = sitePos(ue, :);
        d2d = hypot(pos(1) - site(1), pos(2) - site(2));
        d3d = norm(pos - site);
        doppler = speed_mps * fcHz / c;
        pathloss = basePathloss(ue) + shadow(ue) + o2i(ue);
        rows(rowIdx) = struct( ...
            "Slot", double(slot), ...
            "Time_s", double(t), ...
            "UEID", double(ue), ...
            "CellID", double(ue), ...
            "ServingCell", double(ue), ...
            "X_m", double(pos(1)), ...
            "Y_m", double(pos(2)), ...
            "Z_m", double(pos(3)), ...
            "Speed_kmh", double(cfg.mobility.ue_speed_kmh), ...
            "Speed_mps", double(speed_mps), ...
            "Heading_deg", double(headingDeg), ...
            "Heading_rad", double(headingDeg * pi / 180), ...
            "Distance2D_m", double(d2d), ...
            "Distance3D_m", double(d3d), ...
            "PropagationDelay_s", double(d3d / c), ...
            "RadialVelocity_mps", double(speed_mps), ...
            "ExpectedDopplerHz", double(doppler), ...
            "AppliedDopplerHz", double(doppler), ...
            "SignedDoppler_Hz", double(doppler), ...
            "BasePathloss_dB", double(basePathloss(ue)), ...
            "Pathloss_dB", double(pathloss), ...
            "ShadowFading_dB", double(shadow(ue)), ...
            "O2I_dB", double(o2i(ue)), ...
            "LOSFlag", true, ...
            "LOSState", "LOS", ...
            "PathlossModelSource", "geometry_runtime_fixture", ...
            "PathlossComplianceStatus", "reconciled_fixture", ...
            "LOSProbabilitySource", "geometry_runtime_fixture", ...
            "LOSComplianceStatus", "reconciled_fixture", ...
            "Status", "runtime_trace_complete");
        rowIdx = rowIdx + 1;
    end
end

T = struct2table(rows, "AsArray", true);
end

function T = localTrialTable(direction)
rows = repmat(struct( ...
    "Direction", "", "Slot", NaN, "UEID", NaN, "CellID", NaN, ...
    "MeasuredTrialSINR_dB", NaN, "MeasuredTrialSINRSource", "", ...
    "MCS", NaN, "RankEstimate", NaN, "Layers", NaN, "Modulation", "", "Status", ""), 8, 1);
rowIdx = 1;
for ue = 1:2
    for slot = 1:4
        sinrBase = 18 + ue + 0.25 * slot;
        if upper(string(direction)) == "UL"
            sinrBase = sinrBase - 1.5;
        end
        rows(rowIdx) = struct( ...
            "Direction", upper(string(direction)), ...
            "Slot", double(slot), ...
            "UEID", double(ue), ...
            "CellID", double(ue), ...
            "MeasuredTrialSINR_dB", double(sinrBase), ...
            "MeasuredTrialSINRSource", "runtime_posteq_link_trial", ...
            "MCS", double(16 + ue + slot), ...
            "RankEstimate", double(localTernary(upper(string(direction)) == "DL", 2, 1)), ...
            "Layers", double(localTernary(upper(string(direction)) == "DL", 2, 1)), ...
            "Modulation", localTernary(upper(string(direction)) == "DL", "256QAM", "64QAM"), ...
            "Status", "PASS");
        rowIdx = rowIdx + 1;
    end
end
T = struct2table(rows, "AsArray", true);
end

