function ok = testPDCCHCandidateCapacityResolution()
%TESTPDCCHCANDIDATECAPACITYRESOLUTION Guard bandwidth-derived search space.

scenarioPath = fullfile("simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
runRoot = tempname;
mkdir(runRoot);
cleanup = onCleanup(@() localCleanup(runRoot)); %#ok<NASGU>
cfg = sixgr.config.normalizeConfig( ...
    sixgr.lls6g.buildInternalConfig(scfg, runRoot));

dciBits = int8(mod((0:31).', 2));
[tx5MHz, txInfo5MHz] = sixgr.phy.dl.PDCCH_Tx(cfg, ...
    "DCIBits", dciBits, "K", numel(dciBits), "OFDMModulate", true);
assert(txInfo5MHz.SearchSpaceNCCE == 8, ...
    "The 24-RB, two-symbol CORESET must contain eight CCEs.");
assert(isequal(txInfo5MHz.ConfiguredSearchSpaceNumCandidates, [8 8 4 2 1]), ...
    "Configured search-space intent must remain auditable.");
assert(isequal(txInfo5MHz.ResolvedSearchSpaceNumCandidates, [8 4 2 1 0]), ...
    "Candidate counts must be bounded by CCE capacity and enabled ALs.");
assert(string(txInfo5MHz.SearchSpaceCandidateResolutionSource) == ...
    "configured_bounded_by_coreset_cce_capacity", ...
    "A capacity adjustment must be explicitly disclosed.");
assert(isequal(double(tx5MHz.PDCCH.SearchSpace.NumCandidates), ...
    txInfo5MHz.ResolvedSearchSpaceNumCandidates), ...
    "The resolved candidates must reach the Toolbox search-space object.");
assert(~isempty(tx5MHz.PDCCHInd) && ~isempty(tx5MHz.DMRSInd), ...
    "The capacity-resolved PDCCH must materialize exact resource indices.");
[rx5MHz, rxInfo5MHz] = sixgr.phy.dl.PDCCH_Rx(tx5MHz.Waveform, cfg, ...
    "Carrier", tx5MHz.Carrier, "PDCCH", tx5MHz.PDCCH, ...
    "K", numel(dciBits), "ExpectedDCIBits", dciBits, ...
    "NoiseVar", 1e-12);
assert(rx5MHz.Ok && rx5MHz.CausalGrantDecodeOk && ...
    rx5MHz.DCIPayloadMatch && rxInfo5MHz.CausalGrantDecodeOk, ...
    "The receiver must decode the exact transmitted DCI using the resolved search space.");

cfgLarger = cfg;
cfgLarger.phy.carrier.NSizeGrid = 51;
cfgLarger.phy.pdcch.coreset.frequencyResources = ones(1, 8);
[~, txInfoLarger] = sixgr.phy.dl.PDCCH_Tx(cfgLarger, ...
    "K", 32, "OFDMModulate", false);
assert(txInfoLarger.SearchSpaceNCCE == 16 && ...
    isequal(txInfoLarger.ResolvedSearchSpaceNumCandidates, [8 8 4 2 0]), ...
    ["When the BWP/CORESET grows, AL2/4/8 candidates must expand to " ...
     "the configured values while disabled AL16 remains zero."]);

ok = true;
fprintf('%s\n', ['PASS testPDCCHCandidateCapacityResolution: configured ' ...
    'candidate intent is resolved against dynamic CORESET CCE capacity.']);
end

function localCleanup(pathText)
if isfolder(pathText)
    rmdir(pathText, "s");
end
end
