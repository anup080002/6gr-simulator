function ok=testULCodeBlockCRCIntegrity(outputRoot)
% Actual public UL codecs on declared LLRs; not waveform/BLER evidence.
% Corrupt only a real CRC24B bit BEFORE LDPC encoding. Payload and TB CRC
% stay intact. Retain separate CB/TB CRC and aggregate decoder observations;
% acceptance must match the actual canonical MATLAB TB verdict while CB
% failures remain visible. No verdict is mocked. This is a declared-codec
% regression, not waveform performance or 3GPP conformance qualification.
%
% Active target: decodeResolvedULSCH is used by PUSCH_Rx full two-CW and
% received-UCI partial-map paths. The one-CW invocation below exercises the
% shared decoder, not PUSCH_Rx's separate single-CW waveform branch.
% TS38.212 V18.8.0 6.2.3 -> 5.2.2 defines CRC24B attachment, not a mandated
% decoder stopping/acceptance algorithm. Compare the actual installed
% nrULSCHDecoder/nrDLSCHDecoder with both combined helpers and the active
% repository DLSCHDecoder. Keep MATLAB implementation parity distinct from
% a normative claim about an unspecified decoder algorithm.
setup6GRSimToolkit('Verbose',false);
if nargin<1, outputRoot=tempname(fullfile(pwd,'logs')); end
assert(~isfolder(outputRoot),'test:EvidenceAlreadyExists','Preserve earlier CRC diagnostics.');
mkdir(outputRoot);
cfg=struct('phy',struct('ldpc',struct('maxIterations',25,'algorithm','Normalized min-sum')));
scope="declared_DL_UL_codec_LLR_CRC_acceptance_not_waveform_performance";
runtimeVersion=version; toolboxVersions=ver;
for rank=[1 6]
    layers=sixgr.phy.ul.pusch.PUSCHLayerMapper.layerCounts(rank);
    count=numel(layers); A=10000*ones(1,count); rate=.6*ones(1,count); rv=zeros(1,count);
    if count==1, mods='QPSK'; else, mods={'QPSK','QPSK'}; end
    p=nrPUSCHConfig('NumLayers',rank,'Modulation',mods);
    [goodLLR,bits,layouts,goodStages]=localEncode(layers,A,rate,rv,"none");
    [badLLR,badBits,badLayouts,badStages]=localEncode(layers,A,rate,rv,"cb_crc_only");
    assert(isequal(bits,badBits) && isequaln(layouts,badLayouts));
    good=sixgr.phy.ul.pusch.decodeResolvedULSCH(goodLLR,true(1,count), ...
        p,A,rate,rv,layouts,25,'Normalized min-sum',[],[]);
    bad=sixgr.phy.ul.pusch.decodeResolvedULSCH(badLLR,true(1,count), ...
        p,A,rate,rv,layouts,25,'Normalized min-sum',[],[]);
    goodCanonical=localCanonical(goodLLR,p,A,rate,rv);
    badCanonical=localCanonical(badLLR,p,A,rate,rv);
    goodReference=cell(1,count); badReference=cell(1,count);
    combinedGuard=cell(1,count);
    for cw=1:count
        goodReference{cw}=localReference(goodLLR{cw},A(cw),rate(cw),rv(cw),layers(cw));
        badReference{cw}=localReference(badLLR{cw},A(cw),rate(cw),rv(cw),layers(cw));
        [guardPass,guardIterations,guardBits,guardDiagnostics]=sixgr.phy.harq.decodeCombinedULSCH( ...
            layouts{cw},badReference{cw}.RecoveredLLR,cfg);
        combinedGuard{cw}=struct('DecodePass',guardPass,'Iterations',guardIterations, ...
            'TransportBlock',guardBits,'Diagnostics',guardDiagnostics);
    end
    [dlPlans,activeDL,combinedDL]=localDL(badLLR,layers,A,rate,rv,badReference,cfg);
    [~,goodActiveDL,goodCombinedDL]=localDL(goodLLR,layers,A,rate,rv,goodReference,cfg);
    selected=false(1,count); selected(end)=true;
    partialLLR=badLLR; partialLLR(~selected)={[]};
    partial=sixgr.phy.ul.pusch.decodeResolvedULSCH(partialLLR,selected, ...
        p,A,rate,rv,layouts,25,'Normalized min-sum',[],[]);
    comparison=struct('Kind',"MATLAB_BEHAVIOR_transport_crc_acceptance_not_normative_verdict", ...
        'ResolvedULPass',bad.CRCPass,'PartialULPass',partial.CRCPass, ...
        'CombinedULPass',double(cellfun(@(e)e.DecodePass,combinedGuard)), ...
        'ActiveDLPass',double(activeDL.CRCPassPerCodeword), ...
        'CombinedDLPass',double(cellfun(@(e)e.DecodePass,combinedDL)), ...
        'CanonicalULPass',double(~badCanonical.UL.BlockError), ...
        'CanonicalDLPass',double(~badCanonical.DL.BlockError));
    save(fullfile(outputRoot,sprintf('ul_cb_crc_integrity_rank_%d.mat',rank)), ...
        'scope','rank','p','A','rate','rv','layouts','bits','goodLLR','badLLR', ...
        'goodStages','badStages','good','bad','partial','goodReference', ...
        'badReference','combinedGuard','goodCanonical','badCanonical', ...
        'dlPlans','activeDL','combinedDL','goodActiveDL','goodCombinedDL', ...
        'comparison','runtimeVersion','toolboxVersions');
    % Establish that the stimulus really changed a CB CRC, not the payload,
    % a TB CRC, LDPC parity, or an unobserved mock summary field.
    assert(good.AllTransportBlocksPassed && isequal(good.TransportBlocks,bits));
    assert(~any(goodCanonical.UL.BlockError) && ~any(goodCanonical.DL.BlockError) && ...
        isequal(goodCanonical.UL.TransportBlocks,bits) && ...
        isequal(goodCanonical.DL.TransportBlocks,bits));
    assert(goodActiveDL.CRCPass && isequal(goodActiveDL.TransportBlocks,bits) && ...
        all(cellfun(@(e)e.DecodePass,goodCombinedDL)));
    assert(isequal(comparison.ResolvedULPass,comparison.CanonicalULPass) && ...
        isequal(comparison.CombinedULPass,comparison.CanonicalULPass) && ...
        isequal(comparison.ActiveDLPass,comparison.CanonicalDLPass) && ...
        isequal(comparison.CombinedDLPass,comparison.CanonicalDLPass) && ...
        all(comparison.CanonicalULPass==1) && all(comparison.CanonicalDLPass==1) && ...
        partial.CRCPass(end)==comparison.CanonicalULPass(end));
    for cw=1:count
        expectedError=(cw==count);
        reference=badReference{cw};
        assert(goodReference{cw}.TBCRCError==0 && ...
            ~any(goodReference{cw}.CodeBlockCRCError) && ...
            isequal(goodReference{cw}.TransportBlock,bits{cw}));
        assert(reference.TBCRCError==0 && isequal(reference.TransportBlock,bits{cw}) && ...
            any(reference.CodeBlockCRCError)==expectedError);
        assert(~any(reference.ParityChecks(:)) && ...
            isequal(badCanonical.UL.TransportBlocks{cw},bits{cw}) && ...
            isequal(badCanonical.DL.TransportBlocks{cw},bits{cw}));
        assert(any(badCanonical.UL.DecoderInfo.CodeBlockError{cw})==expectedError && ...
            any(badCanonical.DL.DecoderInfo.CodeBlockError{cw})==expectedError);
        assert(isequal(bad.TransportBlocks{cw},bits{cw}) && ...
            any(bad.CodewordEvidence{cw}.CodeBlockCRCError)==expectedError);
        assert(isequal(combinedGuard{cw}.TransportBlock,bits{cw}));
        localCheckDiagnostics(combinedGuard{cw}.Diagnostics,reference,A(cw),"UL");
        localCheckDiagnostics(combinedDL{cw}.Diagnostics,reference,A(cw),"DL");
        assert(isequal(combinedDL{cw}.TransportBlock,bits{cw}));
        if count==1, dlCodeword=activeDL; else, dlCodeword=activeDL.Codewords{cw}; end
        assert(isequal(dlCodeword.TransportBlock,bits{cw}) && ...
            dlCodeword.TransportBlockCRCPass && ~dlCodeword.TransportBlockCRCError && ...
            isequal(dlCodeword.CodeBlockCRCError,logical(reference.CodeBlockCRCError(:))) && ...
            dlCodeword.CRCPass && ~dlCodeword.CRCError);
        assert(nnz(goodStages{cw}.SegmentedBlocks~=badStages{cw}.SegmentedBlocks)==double(expectedError));
    end
    assert(all(bad.DecodeAttempted) && all(bad.CRCAvailable) && ...
        partial.DecodeAttempted(end) && partial.CRCAvailable(end));
    if count>1
        assert(~partial.DecodeAttempted(1) && ~partial.CRCAvailable(1) && ...
            isnan(partial.CRCPass(1)) && isnan(partial.CRCError(1)));
    end
    fprintf('SCH_CRC_ACCEPTANCE rank=%d tb_crc_pass=1 cb_crc_error=%s resolved_ul_pass=%s combined_ul_pass=%s active_dl_pass=%s combined_dl_pass=%s canonical_ul_pass=%s canonical_dl_pass=%s evidence=%s\n', ...
        rank,mat2str(badReference{end}.CodeBlockCRCError),mat2str(bad.CRCPass), ...
        mat2str(comparison.CombinedULPass),mat2str(comparison.ActiveDLPass), ...
        mat2str(comparison.CombinedDLPass),mat2str(comparison.CanonicalULPass), ...
        mat2str(comparison.CanonicalDLPass),outputRoot);
end
localControls(outputRoot,cfg,scope,runtimeVersion,toolboxVersions);
ok=true;
end

function localControls(outputRoot,cfg,scope,runtimeVersion,toolboxVersions)
for name=["single_cb_valid","segmented_both_crc_fail","segmented_tb_crc_fail"]
    expectedFailure=name~="single_cb_valid";
    expectedCBFailure=name=="segmented_both_crc_fail";
    if expectedCBFailure, A=10000; corruption="tb_and_cb";
    elseif expectedFailure, A=10000; corruption="tb_crc_only";
    else, A=512; corruption="none";
    end
    rate=.6; rv=0; layers=1; p=nrPUSCHConfig('NumLayers',1,'Modulation','QPSK');
    [llr,bits,layouts,stages]=localEncode(layers,A,rate,rv,corruption);
    reference=localReference(llr{1},A,rate,rv,layers);
    canonical=localCanonical(llr,p,A,rate,rv);
    resolved=sixgr.phy.ul.pusch.decodeResolvedULSCH(llr,true,p,A,rate,rv, ...
        layouts,25,'Normalized min-sum',[],[]);
    [guardPass,guardIterations,guardBits,guardDiagnostics]=sixgr.phy.harq.decodeCombinedULSCH( ...
        layouts{1},reference.RecoveredLLR,cfg);
    [dlPlans,activeDL,combinedDL]=localDL(llr,layers,A,rate,rv,{reference},cfg);
    save(fullfile(outputRoot,char(name+".mat")),'scope','name','A','rate','rv', ...
        'p','llr','bits','layouts','stages','reference','canonical','resolved', ...
        'guardPass','guardIterations','guardBits','guardDiagnostics','dlPlans', ...
        'activeDL','combinedDL','runtimeVersion','toolboxVersions');
    assert((reference.TBCRCError~=0)==expectedFailure && ...
        any(reference.CodeBlockCRCError)==expectedCBFailure && ...
        ~any(reference.ParityChecks(:)));
    assert(resolved.CRCPass==~expectedFailure && guardPass==~expectedFailure && ...
        canonical.UL.BlockError==expectedFailure && canonical.DL.BlockError==expectedFailure);
    assert(activeDL.CRCPass==~expectedFailure && combinedDL{1}.DecodePass==~expectedFailure && ...
        isequal(activeDL.TransportBlock,reference.TransportBlock) && ...
        isequal(combinedDL{1}.TransportBlock,reference.TransportBlock));
    localCheckDiagnostics(guardDiagnostics,reference,A,"UL");
    localCheckDiagnostics(combinedDL{1}.Diagnostics,reference,A,"DL");
    assert(isequal(activeDL.CodeBlockCRCError,logical(reference.CodeBlockCRCError(:))));
    assert(isequal(resolved.TransportBlocks{1},reference.TransportBlock) && ...
        isequal(guardBits,reference.TransportBlock) && ...
        isequal(canonical.UL.TransportBlocks{1},reference.TransportBlock) && ...
        isequal(canonical.DL.TransportBlocks{1},reference.TransportBlock));
    if expectedFailure
        assert(stages{1}.ULSCHInfo.C>1 && ...
            isequal(reference.TransportBlock,bits{1})==~expectedCBFailure);
    else
        assert(stages{1}.ULSCHInfo.C==1 && isempty(reference.CodeBlockCRCError) && ...
            isequal(reference.TransportBlock,bits{1}));
    end
end
end

function [plans,active,combined]=localDL(llr,layers,A,rate,rv,references,cfg)
count=numel(llr); plans=cell(1,count); combined=cell(1,count);
for cw=1:count
    plans{cw}=sixgr.pdsch.DLSCHCodingPlan.resolve('TransportBlockSize',A(cw), ...
        'TargetCodeRate',rate(cw),'RV',rv(cw),'Modulation','QPSK', ...
        'NumLayers',layers(cw),'RateMatchedBitCount',numel(llr{cw}),'CodewordIndex',cw-1);
    [pass,iterations,bits,diagnostics]=sixgr.phy.harq.decodeCombinedDLSCH( ...
        plans{cw}.toCodingLayout(),references{cw}.RecoveredLLR,cfg);
    combined{cw}=struct('DecodePass',pass,'Iterations',iterations, ...
        'TransportBlock',bits,'Diagnostics',diagnostics);
end
active=sixgr.pdsch.DLSCHDecoder(llr,'CodingPlan',plans, ...
    'MaxIterations',25,'Algorithm','Normalized min-sum');
end

function localCheckDiagnostics(diagnostics,reference,A,direction)
assert(diagnostics.Direction==direction && ...
    diagnostics.AcceptanceBasis=="transport_block_crc_and_length" && ...
    diagnostics.DecodedTransportBlockLength==A && diagnostics.TransportBlockLengthMatch && ...
    diagnostics.TransportBlockCRCPass==(reference.TBCRCError==0) && ...
    diagnostics.TransportBlockCRCError==(reference.TBCRCError~=0) && ...
    isequal(diagnostics.CodeBlockCRCError,reference.CodeBlockCRCError) && ...
    isequal(diagnostics.CodeBlockCRCPass,~logical(reference.CodeBlockCRCError)) && ...
    diagnostics.CRCPass==diagnostics.TransportBlockCRCPass);
end

function result=localCanonical(llr,p,A,rate,rv)
% A fresh object per invocation prevents accidental combining of the good
% and bad stimuli. Keep real Toolbox block verdicts, not inferred CB policy.
ul=nrULSCHDecoder('MultipleHARQProcesses',false,'TargetCodeRate',rate, ...
    'TransportBlockLength',A,'LDPCDecodingAlgorithm','Normalized min-sum', ...
    'MaximumLDPCIterationCount',25);
dl=nrDLSCHDecoder('MultipleHARQProcesses',false,'TargetCodeRate',rate, ...
    'TransportBlockLength',A,'LDPCDecodingAlgorithm','Normalized min-sum', ...
    'MaximumLDPCIterationCount',25);
if numel(llr)==1, input=llr{1}; else, input=llr; end
[ulBits,ulError]=ul(input,p.Modulation,p.NumLayers,rv);
[dlBits,dlError]=dl(input,p.Modulation,p.NumLayers,rv);
if ~iscell(ulBits), ulBits={ulBits}; end
if ~iscell(dlBits), dlBits={dlBits}; end
result=struct('UL',struct('TransportBlocks',{reshape(ulBits,1,[])}, ...
    'BlockError',logical(reshape(ulError,1,[])),'DecoderInfo',info(ul), ...
    'Source',string(which('nrULSCHDecoder'))), ...
    'DL',struct('TransportBlocks',{reshape(dlBits,1,[])}, ...
    'BlockError',logical(reshape(dlError,1,[])),'DecoderInfo',info(dl), ...
    'Source',string(which('nrDLSCHDecoder'))));
end

function [llr,bits,layouts,stages]=localEncode(layers,A,rate,rv,corrupt)
count=numel(layers); llr=cell(1,count); bits=cell(1,count);
layouts=cell(1,count); stages=cell(1,count);
for cw=1:count
    sch=nrULSCHInfo(A(cw),rate(cw));
    bits{cw}=int8(mod((1:A(cw)).'+floor((1:A(cw)).'/(7+cw)),2));
    withCRC=nrCRCEncode(bits{cw},sch.CRC);
    if corrupt=="tb_crc_only" && cw==count
        % Recompute CB CRC around a genuinely invalid TB CRC. Payload stays
        % unchanged: exact reference bits cannot authorize transport success.
        withCRC(end)=1-withCRC(end);
    end
    segmented=nrCodeBlockSegmentLDPC(withCRC,sch.BGN);
    changedIndex=NaN;
    if corrupt~="none" && cw==count
        assert(sch.C>1,'test:SegmentedTBRequired', ...
            'The corrupted controls require actual CRC24B-bearing code blocks.');
    end
    if corrupt=="cb_crc_only" && cw==count
        % Segmentation appends CRC24B after the binary payload and before
        % filler. Flip exactly its final bit in the first code block.
        changedIndex=find(segmented(:,1)>=0,1,'last');
        segmented(changedIndex,1)=1-segmented(changedIndex,1);
    elseif corrupt=="tb_and_cb" && cw==count
        % Change one actual payload bit after both CRCs were attached.
        % LDPC-encode this input normally so LDPC parity still remains valid.
        changedIndex=1;
        segmented(changedIndex,1)=1-segmented(changedIndex,1);
    end
    coded=nrLDPCEncode(segmented,sch.BGN);
    quantum=2*layers(cw); G=quantum*ceil(2*sch.N*sch.C/quantum);
    matched=nrRateMatchLDPC(coded,G,rv(cw),'QPSK',layers(cw));
    llr{cw}=20*(1-2*double(matched));
    layouts{cw}=sixgr.phy.phycode.resolveCodingLayout('Direction','UL', ...
        'TransportBlockSize',A(cw),'TargetCodeRate',rate(cw),'RV',rv(cw), ...
        'Modulation','QPSK','NumLayers',layers(cw),'RateMatchedBitCount',G);
    stages{cw}=struct('TBWithCRC',withCRC,'SegmentedBlocks',segmented, ...
        'Corruption',corrupt,'ChangedSegmentedRow',changedIndex,'MotherCodeBits',coded, ...
        'RateMatchedBits',matched,'ULSCHInfo',sch);
end
end

function reference=localReference(llr,A,rate,rv,layers)
sch=nrULSCHInfo(A,rate);
recovered=nrRateRecoverLDPC(llr,A,rate,rv,'QPSK',layers);
[decoded,iterations,parity]=nrLDPCDecode(recovered,sch.BGN,25,'Algorithm','Normalized min-sum');
[withCRC,cbError]=nrCodeBlockDesegmentLDPC(decoded,sch.BGN,A+sch.L);
[bits,tbError]=nrCRCDecode(withCRC,sch.CRC);
reference=struct('RecoveredLLR',recovered,'DecodedCodeBlocks',decoded, ...
    'Iterations',iterations,'ParityChecks',parity,'TBWithCRC',withCRC, ...
    'TransportBlock',int8(bits(:)),'TBCRCError',tbError,'CodeBlockCRCError',cbError);
end
