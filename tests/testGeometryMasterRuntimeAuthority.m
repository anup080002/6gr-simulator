function ok = testGeometryMasterRuntimeAuthority()
%TESTGEOMETRYMASTERRUNTIMEAUTHORITY Prove geometry YAML owns runtime grants.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "master_geometry_based.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
resolved = scfg.toStruct();
tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() localCleanup(tmp)); %#ok<NASGU>
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));

assert(strcmpi(char(string(cfg.validation.run_class)), ...
    "ue_placement_geometry_lls"), ...
    "The explicit geometry run class must survive config normalization.");
assert(strcmpi(char(string(cfg.run.pdschExecutionProfile)), ...
    "scheduler_truth"), ...
    "Geometry PDSCH must execute through the scheduler-owned coupled truth profile.");
assert(isequal(double(cfg.phy.pdsch.SymbolAllocation), [2 12]), ...
    "Configured PDSCH TDRA did not reach the internal PHY.");
assert(isequal(double(cfg.phy.pusch.SymbolAllocation), [0 14]), ...
    "Configured PUSCH TDRA did not reach the internal PHY.");
assert(isequal(double(cfg.phy.pdcch.SymbolAllocation), [0 2]), ...
    "Configured PDCCH symbol allocation did not reach the runtime.");
assert(isequal(double(cfg.phy.pdsch.PRBSet), 0:272), ...
    "Configured PDSCH PRB bounds did not reach the internal PHY.");
assert(isequal(double(cfg.phy.pusch.PRBSet), 0:272), ...
    "Configured PUSCH PRB bounds did not reach the internal PHY.");
assert(double(cfg.phy.bwp.dl.NStartBWP) == 0 && ...
    double(cfg.phy.bwp.dl.NSizeBWP) == 273, ...
    "Configured DL active BWP did not reach the frame runtime.");
assert(double(cfg.phy.bwp.ul.NStartBWP) == 0 && ...
    double(cfg.phy.bwp.ul.NSizeBWP) == 273, ...
    "Configured UL active BWP did not reach the frame runtime.");

policy = cfg.phy.frameStructure.TimingContext.Policy;
assert(isequal(double(policy.AllowedK0), 0), ...
    "Configured K0 did not reach the canonical timing policy.");
assert(isequal(reshape(double(policy.AllowedK1), 1, []), 1:8), ...
    "Configured K1 candidate set did not reach the canonical timing policy.");
assert(double(policy.ConfiguredDefaultK1) == 4 && ...
    string(policy.K1SelectionPolicy) == "first_valid_configured" && ...
    ~isfield(policy, "SelectedK1"), ...
    ["The YAML K1 default must remain an auditable preference while " ...
     "first_valid_configured selects the actual K1 per PDSCH grant."]);
assert(isequal(double(policy.AllowedK2), 1), ...
    "Configured K2 did not reach the canonical timing policy.");

state = localFullSlotState(cfg, "DL");
dlBudget = sixgr.truth.CoupledTruthRuntime.configuredSlotBudgetRuntime(state);
assert(isequal(double(dlBudget.SymbolAllocation), [2 12]), ...
    "DL scheduler budget bypassed the configured PDSCH TDRA.");
assert(isequal(double(dlBudget.ControlSymbolAllocation), [0 2]), ...
    "DL scheduler budget bypassed the configured PDCCH allocation.");
assert(isequal(double(dlBudget.PRBSet), 0:272), ...
    "DL scheduler budget bypassed the configured PDSCH PRB set.");

state.CurrentDirection = "UL";
state.CurrentSlotDLAllowed = false;
state.CurrentSlotULAllowed = true;
state.CurrentSlotDLNumSymbols = 0;
state.CurrentSlotULSymbolStart = 0;
state.CurrentSlotULNumSymbols = 14;
ulBudget = sixgr.truth.CoupledTruthRuntime.configuredSlotBudgetRuntime(state);
assert(isequal(double(ulBudget.SymbolAllocation), [0 14]), ...
    "UL scheduler budget bypassed the configured PUSCH TDRA.");
assert(isequal(double(ulBudget.PRBSet), 0:272), ...
    "UL scheduler budget bypassed the configured PUSCH PRB set.");

% Prove the scheduler consumes changed config values rather than literals.
cfgProbe = cfg;
cfgProbe.phy.pdsch.SymbolAllocation = [3 10];
cfgProbe.phy.pdsch.symbolAllocation = [3 10];
cfgProbe.phy.pdsch.PRBSet = 7:16;
cfgProbe.phy.pdsch.prbSet = 7:16;
probeState = localFullSlotState(cfgProbe, "DL");
probeBudget = sixgr.truth.CoupledTruthRuntime.configuredSlotBudgetRuntime(probeState);
assert(isequal(double(probeBudget.SymbolAllocation), [3 10]) && ...
    isequal(double(probeBudget.PRBSet), 7:16), ...
    "Changed YAML-derived PDSCH allocation was replaced by a runtime literal.");

probeState.CurrentSlotDLNumSymbols = 10;
unavailable = sixgr.truth.CoupledTruthRuntime.configuredSlotBudgetRuntime(probeState);
assert(double(unavailable.NPRB) == 0 && isempty(unavailable.PRBSet), ...
    "An unavailable configured TDRA must not be shifted into the TDD partition.");
assert(contains(string(unavailable.UnavailableReason), ...
    "configured_dl_symbol_allocation_not_available"), ...
    "Unavailable configured TDRA must report the fail-closed reason.");

probeState = localFullSlotState(cfgProbe, "DL");
probeState.TimingControlSymbolAllocation = [1 2];
localAssertError(@() sixgr.truth.CoupledTruthRuntime. ...
    configuredSlotBudgetRuntime(probeState), "ControlAllocationOverride");

feedbackState = struct("CurrentSlot", 1, "HARQFeedbackSlots", 99, ...
    "SlotsPerFrame", 20, "CfgMobility", cfg);
timing = struct("Valid", true, "K1", 4, ...
    "FeedbackAbsoluteSlot", 4);
grant = struct("TimingDecision", timing, "K1", 4, ...
    "HARQFeedbackAbsoluteSlot", 4);
dueSlot = sixgr.truth.CoupledTruthRuntime.resolveHARQFeedbackDueSlotRuntime( ...
    feedbackState, 1, 1, grant, "DL");
assert(dueSlot == 5, ...
    "DL HARQ feedback must use the scheduler's canonical K1 decision.");
localAssertError(@() sixgr.truth.CoupledTruthRuntime. ...
    resolveHARQFeedbackDueSlotRuntime( ...
    feedbackState, 1, 1, struct(), "DL"), ...
    "MissingCanonicalK1Decision");

badSchedulerCfg = cfg;
badSchedulerCfg.mac.scheduler.type = "unsupported_test_scheduler";
localAssertError(@() sixgr.truth.CoupledTruthRuntime.createSchedulersRuntime( ...
    badSchedulerCfg, 1, "DL", []), "UnsupportedScheduler");

missingPDCCH = localRemoveNested(resolved, "pdcch.start_symbol");
localAssertError(@() sixgr.lls6g.buildInternalConfig( ...
    missingPDCCH, fullfile(tmp, "missing_pdcch")), ...
    "MissingGeometryRuntimeAuthority");
missingPRB = localRemoveNested(resolved, "pdsch.prb_start");
localAssertError(@() sixgr.lls6g.buildInternalConfig( ...
    missingPRB, fullfile(tmp, "missing_prb")), ...
    "MissingGeometryRuntimeAuthority");
wrongProfile = sixgr.util.structSet( ...
    resolved, "pdsch.execution_profile", "phy_calibration");
localAssertError(@() sixgr.lls6g.buildInternalConfig( ...
    wrongProfile, fullfile(tmp, "wrong_profile")), ...
    "GeometryRequiresSchedulerTruthPDSCH");

ok = true;
end

function state = localFullSlotState(cfg, direction)
state = struct( ...
    "SymbolsPerSlot", 14, ...
    "NumRB", double(cfg.phy.carrier.NSizeGrid), ...
    "CurrentSlot", 1, ...
    "CurrentDirection", char(direction), ...
    "CurrentSlotDLAllowed", true, ...
    "CurrentSlotULAllowed", true, ...
    "CurrentSlotDLSymbolStart", 0, ...
    "CurrentSlotDLNumSymbols", 14, ...
    "CurrentSlotULSymbolStart", 0, ...
    "CurrentSlotULNumSymbols", 14, ...
    "CfgMobility", cfg, ...
    "ControlGating", struct("PDCCHRequired", true));
end

function localAssertError(action, expectedIdentifierFragment)
caught = [];
try
    action();
catch ME
    caught = ME;
end
assert(~isempty(caught), ...
    "Expected failure containing identifier '%s'.", expectedIdentifierFragment);
assert(contains(string(caught.identifier), string(expectedIdentifierFragment)), ...
    "Expected error '%s', received '%s': %s", ...
    expectedIdentifierFragment, string(caught.identifier), string(caught.message));
end

function s = localRemoveNested(s, path)
parts = split(string(path), ".");
s = localRemoveNestedAt(s, parts, 1);
end

function s = localRemoveNestedAt(s, parts, index)
key = char(parts(index));
if index == numel(parts)
    if isfield(s, key)
        s = rmfield(s, key);
    end
    return;
end
if isfield(s, key) && isstruct(s.(key)) && isscalar(s.(key))
    s.(key) = localRemoveNestedAt(s.(key), parts, index + 1);
end
end

function localCleanup(folder)
if isfolder(folder)
    rmdir(folder, "s");
end
end
