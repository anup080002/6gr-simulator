function ok = testPDSCHLDPCEncodingIndependent()
%TESTPDSCHLDPCENCODINGINDEPENDENT Compare with pinned external digests.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
vectorPath = fullfile(fileparts(mfilename("fullpath")), "vectors", "pdsch", ...
    "expected_pdsch_ldpc_external_vectors.csv");
opt = detectImportOptions(vectorPath, "TextType", "string");
opt = setvartype(opt, [ ...
    "CaseID","Implementation","Version","Algorithm","SourceURL", ...
    "SourceArtifactSHA256","TBCRCType","InputBits","InputSHA256", ...
    "CodeBlockSHA256","ExpectedEncodedSHA256","Modulation", ...
    "ExpectedRateMatchedSHA256"], "string");
T = readtable(vectorPath, opt);
assert(height(T) == 2, "External LDPC fixture must contain exactly two rows.");
assert(all(T.Implementation == "py3gpp") && all(T.Version == "0.6.0"), ...
    "External LDPC implementation/version provenance changed.");
assert(all(T.SourceArtifactSHA256 == ...
    "1182b03eed6aa44e1af49df827d2712206189a620fd85985e7b795bef11c9aa9"), ...
    "External py3gpp wheel digest changed.");

for i = 1:height(T)
    row = T(i, :);
    bits = int8(reshape(char(row.InputBits), [], 1) - double('0'));
    assert(localSHA256(bits) == row.InputSHA256, ...
        "%s frozen input digest mismatch.", row.CaseID);

    tbCRC = sixgr.phy.tb.attachCRC(bits, row.TBCRCType);
    [codeBlocks, segInfo] = sixgr.phy.tb.segmentLDPC(tbCRC, row.BGN);
    if double(row.BGN) == 1
        actualZc = size(codeBlocks, 1) / 22;
    else
        actualZc = size(codeBlocks, 1) / 10;
    end
    assert(actualZc == double(row.Zc), ...
        "%s lifting size mismatch.", row.CaseID);
    assert(localSHA256(codeBlocks) == row.CodeBlockSHA256, ...
        "%s segmented code-block digest mismatch.", row.CaseID);
    encoded = sixgr.phy.phycode.ldpcEncode(codeBlocks, row.BGN);
    assert(localSHA256(encoded) == row.ExpectedEncodedSHA256, ...
        "%s external LDPC mother-code digest mismatch.", row.CaseID);
    rateMatched = sixgr.phy.phycode.rateMatchLDPC( ...
        encoded, row.G, row.RV, row.Modulation, row.NumLayers);
    assert(localSHA256(rateMatched) == row.ExpectedRateMatchedSHA256, ...
        "%s external rate-matched digest mismatch.", row.CaseID);

    plan = sixgr.pdsch.DLSCHCodingPlan.resolve( ...
        "TransportBlockSize", row.A, ...
        "TargetCodeRate", row.R, ...
        "RateMatchedBitCount", row.G, ...
        "RV", row.RV, ...
        "Modulation", row.Modulation, ...
        "NumLayers", row.NumLayers);
    staged = sixgr.pdsch.DLSCHEncoder(bits, plan);
    assert(localSHA256(staged.EncodedCodeBlocks) == row.ExpectedEncodedSHA256, ...
        "%s explicit encoder did not preserve the external parity fixture.", row.CaseID);
    assert(localSHA256(staged.RateMatchedBits) == ...
        row.ExpectedRateMatchedSHA256, ...
        "%s explicit encoder did not preserve external rate matching.", row.CaseID);
end

fprintf("PDSCH independent external LDPC fixtures: 2/2 exact, digest mismatches=0\n");
ok = true;
end

function value = localSHA256(data)
md = java.security.MessageDigest.getInstance("SHA-256");
md.update(typecast(int8(data(:)), "uint8"));
digest = typecast(int8(md.digest()), "uint8");
value = string(lower(reshape(dec2hex(digest, 2).', 1, [])));
end
