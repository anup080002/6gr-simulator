function [ok,fixture]=testCellRARWaveformPreparation()
% Actual canonical common-control/data preparation; declared detector input.
% No shared TX RF, propagation, UE decode or access completion is claimed.
[~,f]=testCellRARTransmissionContext();
ra=f.RAContext; names=["ServingCell","CellId","PRACHAbsoluteSlot", ...
    "PRACHOccasionSymbol","PRACHFrequencyIndex","RARNTI"];
cellContext=struct();for name=names,cellContext.(name)=ra.(name);end
allocator=sixgr.mac.ra.RARIdentityAllocator(f.Config.random_access.temporary_crnti_pool);
[plan,next]=sixgr.mac.ra.buildCellRARResponsePlan(cellContext,f.Policy, ...
    f.DeclaredReceiverReceipt.AdmittedDetections, ...
    f.DeclaredReceiverReceipt.Plan.SampleRateHz,allocator,[]);
assert(isempty(allocator.Allocations) && numel(next.Allocations)==1);
before=rng;
allocation=sixgr.phy.ra.generateMsg2RARWaveform(f.TXConfig,ra,struct(),'AllocationOnly',true);
assert(isequal(before,rng) && ~isfield(allocation,'Waveform') && ...
    allocation.TransportBlockSize>=plan.RAR.BitLength);
p=sixgr.truth.prepareCellRARTransmission(f.TXConfig,ra,plan);
assert(p.RFExecutionDeferred && p.ExecutionStatus=="generated_not_propagated" && ...
    p.Tx.PDSCHExecutionProfile=="ra_si_strict" && p.Tx.RARDCIContextDigest==p.Schedule.DCIContext.Digest && ...
    p.Tx.RARDCIReferenceSource=="original_gNB_configured_mib_coreset0" && ...
    p.TransmitStartSample>=ra.ReceiverCompletedAtSample && ...
    size(p.PhysicalWaveform,1)==p.SampleCount && ...
    size(p.PhysicalWaveform,2)==p.PhysicalPortCount && all(isfinite(p.PhysicalWaveform),'all') && ...
    any(p.PhysicalWaveform~=0,'all') && p.PortCount==1 && ...
    p.RAContext.UEId==0 && numel(p.CommonResourceReservations)==2);
assert(isequal(p.Tx.RAR.Bytes,plan.RAR.Bytes) && ...
    isequal(p.Tx.TransportBlockBits(1:numel(plan.RAR.Bits)),plan.RAR.Bits) && ...
    p.Tx.TransportBlockSize==allocation.TransportBlockSize);
bad=plan;bad.RAR.Bytes(1)=bitxor(bad.RAR.Bytes(1),uint8(1));
try
    sixgr.truth.prepareCellRARTransmission(f.TXConfig,ra,bad);
    error('test:CellRARGuard','Tampered original RAR plan accepted.');
catch e
    assert(string(e.identifier)=="sixgr:truth:CellRARPreparationContract");
end
ok=true;
fixture=struct('Prepared',p,'Original',f);
fprintf('CELL_RAR_PREPARATION_PASS canonical_PDCCH_PDSCH=1 shared_RF=0 UE_decode=0\n');
end
