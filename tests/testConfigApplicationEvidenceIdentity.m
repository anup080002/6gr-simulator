function ok = testConfigApplicationEvidenceIdentity()
%TESTCONFIGAPPLICATIONEVIDENCEIDENTITY Guard repeated real application events.

setup6GRSimToolkit("Verbose", false);
cleanup = onCleanup(@() sixgr.config.publishConfigApplicationEvidence("clear")); %#ok<NASGU>
sixgr.config.publishConfigApplicationEvidence("reset", ...
    struct("RunId", 7, "ScenarioID", "identity_unit", "RunTag", "run_1"));
for index = 1:2
    sixgr.config.publishConfigApplicationEvidence("record", ...
        "frequency.center_frequency_hz", "Carrier_Numerology_Grid", ...
        "channel.fc_Hz", "tests.runtimeConsumer", 3.5e9, ...
        "RuntimeObjectType", "Carrier", ...
        "RuntimeObjectPath", "carrier.CenterFrequency", ...
        "ApplicationScope", "runtime_object");
end
T = sixgr.config.publishConfigApplicationEvidence("snapshot");
assert(height(T) == 2 && ...
    all(ismember(["ApplicationEventSequence","ApplicationEventID"], ...
    string(T.Properties.VariableNames))), ...
    "Config application evidence must expose a stable per-event identity.");
assert(isequal(T.ApplicationEventSequence, [1;2]) && ...
    numel(unique(string(T.ApplicationEventID))) == 2 && ...
    all(string(T.RunId) == "7") && ...
    height(unique(T, "rows", "stable")) == height(T), ...
    "Repeated applications to the same runtime object are distinct events, not duplicate rows.");

ok = true;
fprintf("testConfigApplicationEvidenceIdentity: PASS\n");
end
