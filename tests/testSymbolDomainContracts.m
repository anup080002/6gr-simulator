function ok = testSymbolDomainContracts()
%TESTSYMBOLDOMAINCONTRACTS Layer/port/bit-domain contracts for PHY metrics.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
if ~localHaveRequired5G()
    warning("testSymbolDomainContracts:Missing5G", ...
        "Skipping symbol-domain contract tests because required 5G Toolbox APIs are unavailable.");
    ok = true;
    return;
end

rng(7303, "twister");
cfg = localULCodebookCfg();
[tx, ~] = sixgr.phy.ul.PUSCH_Tx(cfg, "CompactOutput", false);
[rx, ~] = sixgr.phy.ul.PUSCH_Rx(tx.Waveform, cfg, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "PUSCHIndices", tx.PUSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", 1e-12, ...
    "NoiseVarDomain", "grid", ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true);
[metrics, ~] = sixgr.link.deriveModulationTrackingMetrics(tx, rx, cfg, "UL");

ber = sum(tx.TransportBlock(:) ~= rx.TransportBlock(:)) / numel(tx.TransportBlock);
assert(logical(rx.Ok) && ~logical(rx.CRCError), ...
    "No-noise audited UL loopback must pass TB CRC.");
assert(ber == 0, "No-noise audited UL loopback must have BER=0.");
assert(metrics.SymbolErrorRate == 0 && metrics.SymbolErrors == 0, ...
    "BER=0 and CRC pass must imply layer-domain SER=0 in no-noise loopback.");
assert(strcmpi(string(metrics.SymbolComparisonDomain), "layer"), ...
    "SER/EVM metrics must declare layer-domain comparison.");
assert(size(tx.PUSCHLayerSymbols, 2) == 1 && size(tx.PUSCHPortSymbols, 2) == 2, ...
    "Two-port one-layer PUSCH must retain one layer column and two port columns.");
assert(double(tx.PortIndexCellCount) == 2 * double(tx.QAMSymbolCount), ...
    "Two-port one-layer PUSCH port symbol cells must be twice the layer QAM symbols.");
assert(double(tx.RateMatchedBitCount) == double(tx.G), ...
    "RateMatchedBitCount must equal the PUSCH G bit budget.");
assert(double(metrics.DemapperLLRCount) == double(metrics.RateMatchedBitCount), ...
    "DemapperLLRCount must equal G for this one-codeword PUSCH case.");

localAssertOneInjectedSymbolError(cfg);
localAssertDomainMismatchThrows(cfg);

fprintf("SymbolDomainContracts: CRC=%d BER=%g SER=%g layerSymbols=%d portCells=%d G=%d\n", ...
    logical(rx.Ok), ber, metrics.SymbolErrorRate, ...
    double(tx.QAMSymbolCount), double(tx.PortIndexCellCount), double(tx.RateMatchedBitCount));
ok = true;
end

function cfg = localULCodebookCfg()
cfg = sixgr.config.defaultConfig();
cfg.run.strictNoiseVarianceRequired = false;
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.phy.nTxAnt = 2;
cfg.phy.nRxAnt = 2;
cfg.channel.nTxAnt = 2;
cfg.channel.nRxAnt = 2;
cfg.phy.carrier.NSizeGrid = 12;
cfg.phy.carrier.SubcarrierSpacing = 30;
cfg.phy.pusch.prbSet = 0:5;
cfg.phy.pusch.symbolAllocation = [0 10];
cfg.phy.pusch.modulation = "QPSK";
cfg.phy.pusch.codeRate = 0.30;
cfg.phy.pusch.mcsIndex = 4;
cfg.phy.pusch.numLayers = 1;
cfg.phy.pusch.nLayers = 1;
cfg.phy.pusch.transmissionScheme = "codebook";
cfg.phy.pusch.numAntennaPorts = 2;
cfg.phy.pusch.TPMI = 0;
cfg.phy.pusch.enablePTRS = false;
cfg.phy.pusch.transformPrecoding = false;
cfg.phy.pusch.equalizer = "MMSE";
cfg.phy.channelEstimation.method = "LS";
end

function localAssertOneInjectedSymbolError(cfg)
ref = 0.5 * [1+1i; -1+1i; 1-1i; -1-1i];
est = ref;
est(2) = ref(3);
tx = struct( ...
    "PUSCH", struct("Modulation", "QPSK"), ...
    "PUSCHLayerSymbolsForEvidence", ref, ...
    "LayerSymbolDomain", "layer", ...
    "QAMSymbolCount", numel(ref), ...
    "PortIndexCellCount", numel(ref), ...
    "RateMatchedBitCount", 2 * numel(ref));
rx = struct( ...
    "LayerEqualizedSymbolsForEvidence", est, ...
    "EqualizedSymbolDomain", "layer", ...
    "DemapperLLRCount", 2 * numel(ref));
[metrics, ~] = sixgr.link.deriveModulationTrackingMetrics(tx, rx, cfg, "UL");
assert(metrics.SymbolErrors == 1 && metrics.SymbolsCompared == numel(ref), ...
    "One injected layer-symbol error must produce exactly one SER event.");
assert(metrics.SymbolDecisionBitErrors > 0, ...
    "One injected constellation decision error must produce corresponding bit-domain errors.");
end

function localAssertDomainMismatchThrows(cfg)
tx = struct( ...
    "PUSCH", struct("Modulation", "QPSK"), ...
    "PUSCHLayerSymbolsForEvidence", complex(ones(4, 2)), ...
    "LayerSymbolDomain", "layer");
rx = struct( ...
    "LayerEqualizedSymbolsForEvidence", complex(ones(4, 1)), ...
    "EqualizedSymbolDomain", "layer");
thrown = false;
try
    sixgr.link.deriveModulationTrackingMetrics(tx, rx, cfg, "UL");
catch ME
    thrown = strcmp(ME.identifier, "sixgr:link:SymbolDomainMismatch");
end
assert(thrown, "Layer/port or shape domain mismatch must throw a SymbolDomainMismatch error.");
end

function tf = localHaveRequired5G()
tf = exist("nrPUSCH", "file") == 2 && ...
    exist("nrPUSCHDecode", "file") == 2 && ...
    exist("nrOFDMDemodulate", "file") == 2 && ...
    exist("nrChannelEstimate", "file") == 2;
end
