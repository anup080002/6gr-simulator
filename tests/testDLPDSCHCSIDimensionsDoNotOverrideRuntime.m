function ok = testDLPDSCHCSIDimensionsDoNotOverrideRuntime()
%TESTDLPDSCHCSIDIMENSIONSDONOTOVERRIDERUNTIME Guard CSI/PDSCH axes.
% A CSI-RS state is a reporting input.  Its resource/snapshot axes must not
% be exported as physical PDSCH receive branches or transmit ports.

setup6GRSimToolkit("Verbose", false);
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile(pwd, ...
    "simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring.yaml"));
artifactParent = fullfile(pwd, 'logs', 'embedded_csi_dimensions');
if ~isfolder(artifactParent), mkdir(artifactParent); end
tmp = tempname(artifactParent);
mkdir(tmp);
% Each invocation owns a new folder. Keep completed evidence on either
% success or failure; never remove a previous invocation's artifacts.
fprintf('EMBEDDED_CSI_FIXTURE_ROOT=%s\n', tmp);
cfg = sixgr.lls6g.buildInternalConfig(scenario, tmp);
% Match the normal isolated-link setup. Enabled evidence captures need an
% existing runtime root and the same installed antenna objects as the PHY;
% the fixed-link owner explicitly leaves geometry unavailable.
cfg.run.rootRunFolder = tmp;
cfg = sixgr.truth.attachFixedLinkRuntimeAntennaContext(cfg, 1, 1);
cfg.lls6g.userContext.UEIndex = 1;
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.phy.pdsch.executionProfile = "phy_calibration";
cfg.run.pdschExecutionProfile = "phy_calibration";
cfg.phy.csirs.period_slots = 1;
cfg.phy.csirs.offset_slots = 0;

% Calibration owns this explicit native selection; it is not a received-CSI
% decision or a scheduler grant. Preserve the configured rank/port domain
% and the native matrix normalization, including its exact selected digest.
assert(logical(sixgr.util.structGet(cfg, "mimo.strict", ...
    sixgr.util.structGet(cfg, "phy.mimo.strict", false))) && ...
    cfg.phy.pdsch.numLayers == 2 && ...
    cfg.phy.pdsch.NumAntennaPorts == 2, ...
    'test:EmbeddedCSIRSNativePrecoderDomain', ...
    'The declared calibration fixture must retain strict rank-2/two-port MIMO.');
[candidates, codebookInfo] = sixgr.phy.dl.pmiCodebookCandidates(cfg, ...
    cfg.phy.pdsch.numLayers, cfg.phy.pdsch.NumAntennaPorts);
selected = find([candidates.PMI] == 0);
assert(isscalar(selected), 'test:EmbeddedCSIRSNativePrecoderSelection', ...
    'The configured native codebook must contain exactly one declared PMI zero.');
candidate = candidates(selected);
selectedSHA = string(sixgr.phy.mimo.MatrixContract.digest(candidate.W));
assert(string(candidate.MatrixSHA256) == selectedSHA && ...
    string(candidate.NormalizationConvention) == "unit_frobenius" && ...
    string(codebookInfo.NormalizationConvention) == "unit_frobenius" && ...
    string(cfg.phy.pdsch.precoding.normalizationConvention) == "unit_frobenius", ...
    'test:EmbeddedCSIRSNativePrecoderAuthority', ...
    'Native candidate identity and configured normalization must already agree.');
cfg.phy.pdsch.precoding.matrix = candidate.W;
cfg.phy.pdsch.selectedPrecoderSHA256 = selectedSHA;

% The base fixture has an enabled SS/PBCH burst in absolute slots0/1 and
% SI in slot2. A standalone fixed full-band grant at slot0 correctly fails
% DM-RS collision validation. Use the authored disjoint CSI occasion at3,
% keeping all reference signals and exact allocation guards enabled.
startSlot=4;
scheduled=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,startSlot,1);
carrier=sixgr.phy.grid.makeCarrier(scheduled);
ssb=sixgr.phy.frame.ssbPRBSymbolReservation(scheduled,carrier,startSlot-1);
assert(cfg.phy.ssb.enable && isempty(ssb.ReservedCarrierRE0) && ...
    sixgr.phy.refsig.csirsOccasion(scheduled,startSlot-1), ...
    'test:EmbeddedCSIRSLegalOccasion', ...
    'Keep SSB enabled and execute an actual disjoint CSI/PDSCH occasion.');
sixgr.phy.grid.allocREsPDSCH(carrier,scheduled);
result = sixgr.link.runDLPDSCHThroughput(cfg, "NumFrames", 1, ...
    "StartSlotIndex",startSlot,"StartFrameIndex",1, ...
    "SNR_dB", 30, "ExecutionProfile", "phy_calibration");
assert(istable(result.TrialTable) && ~isempty(result.TrialTable), ...
    "The focused 2x2 PDSCH/CSI-RS chain did not produce runtime trials.");
fprintf(['EMBEDDED_CSI_ACTUAL Rx=%s Tx=%s Frame=%s Slot=%s SFN=%s ' ...
    'RuntimeAbs0=%s CarrierNSlot=%s Layers=%s CRCPass=%s ' ...
    'SelectedSHA=%s AppliedSHA=%s Root=%s\n'], ...
    mat2str(double(result.TrialTable.NumRxAntennas).'), ...
    mat2str(double(result.TrialTable.NumTxPorts).'), ...
    mat2str(double(result.TrialTable.Frame).'), ...
    mat2str(double(result.TrialTable.Slot).'), ...
    mat2str(double(result.TrialTable.SFN).'), ...
    mat2str(double(result.TrialTable.RuntimeAbsoluteSlotIndex0).'), ...
    mat2str(double(result.TrialTable.CarrierNSlot).'), ...
    mat2str(double(result.TrialTable.PrecodingNumLayers).'), ...
    mat2str(double(result.TrialTable.CRCPass).'), ...
    char(selectedSHA), char(join(string(result.TrialTable.AppliedPrecoderMatrixSHA256), ',')), tmp);
assert(all(double(result.TrialTable.NumRxAntennas) == 2) && ...
    all(double(result.TrialTable.NumTxPorts) == 2), ...
    "CSI reporting tensors must not overwrite the executed 2x2 PDSCH waveform dimensions.");
assert(all(string(result.TrialTable.AppliedPrecoderMatrixSHA256) == selectedSHA) && ...
    all(double(result.TrialTable.PrecodingNumLayers) == 2), ...
    'test:EmbeddedCSIRSNativePrecoderApplied', ...
    'Actual calibration PDSCH must apply the exact selected native rank-2 matrix.');
assert(istable(result.CSIRSTrialTable) && ~isempty(result.CSIRSTrialTable) && ...
    all(double(result.CSIRSTrialTable.HestRxPorts) == 2) && ...
    all(double(result.CSIRSTrialTable.HestTxPorts) == 2), ...
    "CSI-RS evidence must independently retain its exact 2x2 channel axes.");
assert(height(result.CSIRSTrialTable)==height(result.TrialTable) && ...
    isequal(result.CSIRSTrialTable.Frame,result.TrialTable.Frame) && ...
    isequal(result.CSIRSTrialTable.Slot,result.TrialTable.Slot) && ...
    isequal(result.CSIRSTrialTable.SFN,result.TrialTable.SFN) && ...
    isequal(result.CSIRSTrialTable.SFN,mod(result.TrialTable.CarrierNFrame,1024)), ...
    'test:EmbeddedCSIRSExecutedClock', ...
    'Embedded CSI-RS and PDSCH must publish the same executed carrier SFN, not Frame.');
assert(cfg.outputs.phySignalDiagnosticEnabled && result.SignalDiagnostic.Available && ...
    istable(result.SignalDiagnostic.SourceTable) && ...
    ~isempty(result.SignalDiagnostic.SourceTable) && height(result.TrialTable) == 1, ...
    'test:EmbeddedCSIRSDiagnosticAvailable', ...
    'The actual single-trial receiver must retain its enabled signal diagnostic.');
diagnostic = result.SignalDiagnostic.SourceTable;
trial = result.TrialTable;
assert(trial.Frame == 1 && trial.Slot == startSlot && ...
    all(diagnostic.Frame == trial.Frame) && all(diagnostic.Slot == trial.Slot) && ...
    all(diagnostic.SFN == trial.SFN) && ...
    all(diagnostic.AbsoluteSlot == trial.RuntimeAbsoluteSlotIndex0) && ...
    all(diagnostic.RuntimeAbsoluteSlotIndex0 == trial.RuntimeAbsoluteSlotIndex0) && ...
    all(diagnostic.CarrierNFrame == trial.CarrierNFrame) && ...
    all(diagnostic.CarrierNSlot == trial.CarrierNSlot) && ...
    all(diagnostic.SlotConvention == "one_based_absolute_slot") && ...
    all(diagnostic.AbsoluteSlotConvention == "zero_based_absolute_slot"), ...
    'test:EmbeddedCSIRSDiagnosticExecutedClock', ...
    'Diagnostic clocks must match the actual carrier without relabeling Frame or Slot.');
ok = true;
fprintf("testDLPDSCHCSIDimensionsDoNotOverrideRuntime: PASS\n");
end
