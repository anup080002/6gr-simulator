function ok = testCSIRSRPPhysicalMeasurement()
%TESTCSIRSRPPHYSICALMEASUREMENT Validate physical CSI-RSRP on the real DL chain.

setup6GRSimToolkit("Verbose", false);
cfg = sixgr.config.defaultConfig();
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.phy.nTxAnt = 1;
cfg.phy.nRxAnt = 1;
cfg.phy.pdsch.enable = true;
cfg.phy.pdsch.nLayers = 1;
cfg.phy.pdsch.numLayers = 1;
cfg.phy.pdsch.SymbolAllocation = [2 12];
cfg.phy.pdsch.symbolAllocation = [2 12];
cfg.phy.pdsch.MappingType = "A";
cfg.phy.pdsch.mappingType = "A";
cfg.phy.pdsch.PRBSet = 0:(double(cfg.phy.carrier.NSizeGrid) - 1);
cfg.phy.pdsch.prbSet = cfg.phy.pdsch.PRBSet;
cfg.phy.pdsch.mcsTable = "calibration_explicit";
cfg.phy.pdsch.mcsIndex = 0;
cfg.phy.csirs.enable = true;
cfg.phy.csirs.period_slots = 1;
cfg.phy.csirs.offset_slots = 0;
cfg.phy.csirs.numResources = 1;
cfg.phy.csirs.nPorts = 1;
cfg.phy.csirs.rowNumber = 2;
cfg.phy.csirs.symbolLocations = 6;
cfg.phy.csirs.subcarrierLocations = 0;
cfg.phy.csirs.rbOffset = 0;
cfg.phy.csirs.numRB = double(cfg.phy.carrier.NSizeGrid);
cfg.phy.csirs.density = "one";
cfg.phy.csirs.precoderMatrices = 1;
cfg.phy.csirs.precoderDigests = ...
    sixgr.phy.mimo.MatrixContract.digest(cfg.phy.csirs.precoderMatrices);
cfg.phy.csirs.precoderBeamIndices = 0;
cfg.phy.csirs.precoderCodebookType = "focused_test_unit_norm_physical_precoder";
cfg = sixgr.util.structSet(cfg, "rf.rx.agc.enable", false);
cfg = sixgr.util.structSet(cfg, "rf.rx.agc.targetRms", 0.25);
cfg = sixgr.util.structSet(cfg, "rf.rx.agc.maxGain_dB", 120);
cfg = sixgr.util.structSet(cfg, "rf.rx.agc.minGain_dB", -120);
cfg = sixgr.util.structSet(cfg, "rf.adc.enable", false);

resultNoAGC = sixgr.link.runDLPDSCHThroughput(cfg, "NumFrames", 1, ...
    "SNR_dB", 20, "ExecutionProfile", "phy_calibration");
cfg = sixgr.util.structSet(cfg, "rf.rx.agc.enable", true);
result = sixgr.link.runDLPDSCHThroughput(cfg, "NumFrames", 1, ...
    "SNR_dB", 20, "ExecutionProfile", "phy_calibration");
assert(istable(result.CSIRSTrialTable) && height(result.CSIRSTrialTable) == 1, ...
    "The production DL chain must emit one measured CSI-RS runtime row.");
row = result.CSIRSTrialTable(1,:);
rowNoAGC = resultNoAGC.CSIRSTrialTable(1,:);
requiredLineage = ["CSIMeasurementID","CSIMeasurementDigest", ...
    "CSIMeasurementProvenance","CSIMeasurementStateAvailable", ...
    "CSIMeasurementStatus","TxMeasurementMethod", ...
    "TxMeasurementMappedREPerAntenna"];
assert(all(ismember(requiredLineage, string(row.Properties.VariableNames))), ...
    "Canonical CSI-RS rows must preserve receiver identity and exact Tx measurement lineage.");
fprintf(["CSI measured state: available=%d status=%s id=%s digest_len=%d " + ...
    "provenance=%s computation=%s channel_estimate=%d canonical_available=%d " + ...
    "cqi=%g ri=%g pmi=%g cri=%g\n"], ...
    logical(row.CSIMeasurementStateAvailable), string(row.CSIMeasurementStatus), ...
    string(row.CSIMeasurementID), strlength(string(row.CSIMeasurementDigest)), ...
    string(row.CSIMeasurementProvenance), string(row.CSIComputationStatus), ...
    logical(row.ChannelEstimateAvailable), logical(row.CSIMeasurementAvailable), ...
    double(row.CQI), double(row.RI), double(row.PMI), double(row.CRI));
assert(strlength(strtrim(string(row.CSIMeasurementID))) > 0 && ...
    strlength(strtrim(string(row.CSIMeasurementDigest))) == 64 && ...
    startsWith(string(row.CSIMeasurementProvenance), "measured_") && ...
    logical(row.CSIMeasurementStateAvailable) && ...
    string(row.CSIMeasurementStatus) == "runtime_measured_state_ready", ...
    "Every executed CSI-RS observation must retain immutable measured-state identity.");
assert(logical(row.Transmitted) && logical(row.Observed) && ...
    logical(row.ResourceExtractionAvailable), ...
    "CSI-RSRP qualification requires the transmitted runtime CSI-RS resource.");
assert(strcmpi(string(row.PhysicalMeasurementStatus), "available") && ...
    isfinite(double(row.MeasurementRSRP_dBm)), ...
    "Physical CSI-RSRP must be available when the runtime PowerContext is sqrt(mW).");
fprintf("CSI-RSRP relative=%.12g dB physical=%.12g dBm no_agc_physical=%.12g dBm scale=%.12g Nfft=%.0f\n", ...
    double(row.MeasurementRelativeRSRP_dB), double(row.MeasurementRSRP_dBm), ...
    double(rowNoAGC.MeasurementRSRP_dBm), ...
    double(row.MeasurementGridScaleToSqrtW), double(row.MeasurementFFTSize));
assert(abs(double(row.MeasurementRSRP_dBm) - ...
    double(rowNoAGC.MeasurementRSRP_dBm)) < 1e-8, ...
    ["Physical CSI-RSRP must be invariant to receiver AGC because it is " ...
    "measured at the pre-front-end antenna reference plane."]);
trialNoAGC = resultNoAGC.TrialTable(1,:);
trial = result.TrialTable(1,:);
assert(logical(trial.AGCApplied) && isfinite(double(trial.AGCGain_dB)) && ...
    abs(double(trial.AGCGain_dB)) > 1, ...
    "The focused AGC case must apply a nontrivial measured receiver gain.");
relativeDelta = double(row.MeasurementRelativeRSRP_dB) - ...
    double(rowNoAGC.MeasurementRelativeRSRP_dB);
assert(abs(relativeDelta - double(trial.AGCGain_dB)) < 1e-8, ...
    ["The post-front-end relative CSI-RS grid power must track the exact " ...
    "AGC gain while physical dBm remains invariant."]);
assert(~logical(trialNoAGC.AGCApplied), ...
    "The no-AGC control trial must retain an identity receiver gain stage.");
assert(strcmpi(string(row.PhysicalMeasurementStandard), ...
    "3GPP_TS_38.215_via_nrCSIRSMeasurements"));
assert(strcmpi(string(row.MeasurementSource), ...
    "nrCSIRSMeasurements_runtime_pre_front_end_antenna_plane_grid"));
assert(strcmpi(string(row.MeasurementRelativeSource), ...
    "received_csirs_reference_signal_power_post_front_end_normalized_grid"));
assert(strcmpi(string(row.PhysicalMeasurementWaveformStatus), ...
    "available_exact_pre_front_end_grid") && ...
    strcmpi(string(row.MeasurementReceiverGainCorrectionSource), ...
    "not_required_exact_pre_front_end_measurement_waveform") && ...
    double(row.MeasurementReceiverGainCorrection_dB) == 0);
assert(strcmpi(string(row.MeasurementAntennaAggregation), ...
    "maximum_per_receive_antenna_rsrp_ts_38_215_diversity_rule"), ...
    "CSI-RSRP must follow the TS 38.215 receiver-diversity reporting rule.");
assert(isfinite(double(trial.CSI_RSRP_dBm)) && ...
    abs(double(trial.CSI_RSRP_dBm) - double(row.MeasurementRSRP_dBm)) < 1e-8, ...
    "The canonical DL trial must preserve the receiver's physical CSI-RSRP dBm measurement.");
assert(abs(double(trial.CSI_RSRP_dB) - ...
    double(row.MeasurementRelativeRSRP_dB)) < 1e-8, ...
    "Normalized CSI-RS grid power must remain separate from physical dBm.");
assert(strcmpi(string(trial.CSI_RSRPPhysicalStatus), "available") && ...
    strcmpi(string(trial.CSI_RSRPPowerReferencePlane), ...
    "receiver_antenna_connector_pre_composite_front_end"));
assert(isfinite(double(row.ReferenceMeasuredSINR_dB)) && ...
    strcmpi(string(row.ReferenceMeasuredSINRStatus), "available") && ...
    strcmpi(string(row.ReferenceMeasuredSINRSource), ...
    "csirs_resource_selective_hest_over_measured_noise_interference_variance"), ...
    "CSI-SINR must come from the CSI-RS estimate/noise plane, not PDSCH post-equalization SINR.");
fprintf("CSI scheduling input: sinr=%.12g dB cqi=%g source=%s role=%s status=%s\n", ...
    double(row.SINR_dB), double(row.CQI), string(row.SINRSource), ...
    string(row.SINRValueRole), string(row.SINRValueStatus));
assert(isfinite(double(row.CQI)) && isfinite(double(row.SINR_dB)) && ...
    ~contains(lower(string(row.SINRSource)), "unavailable") && ...
    strcmpi(string(row.SINRValueStatus), "OK"), ...
    char("A persisted receiver CQI must retain the finite measured effective " + ...
    "SINR from the same CSI report engine; CQI with unavailable SINR is " + ...
     "an invalid scheduling artifact."));

% Exercise the same receiver measurement through the coupled geometry and
% large-scale-power authority used by complete LLS scenarios.  The
% absolute CSI-RS result must move by exactly the applied large-scale gain;
% receiver AGC is downstream of this reference plane and cannot appear in
% the closure equation.
cfgCoupled = cfg;
cfgCoupled.phy.pdsch.mcsTable = "qam64_table1";
cfgCoupled = sixgr.util.structSet(cfgCoupled, "rf.rx.agc.enable", true);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "channel.pathlossEnabled", true);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "channel.pathloss.enabled", true);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "channel.pathlossModel", "nrPathLoss");
cfgCoupled = sixgr.util.structSet(cfgCoupled, "channel.pathloss.model", "nrPathLoss");
cfgCoupled = sixgr.util.structSet(cfgCoupled, "channel.shadowFadingEnabled", false);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "channel.losEnabled", true);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "scenario.layout.nSites", 1);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "scenario.layout.nSectorsPerSite", 1);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "scenario.layout.wrapAround", false);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "scenario.nUE", 1);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "scenario.ue.nUE", 1);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "scenario.bs.nTxAnt", 1);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "scenario.bs.nRxAnt", 1);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "scenario.ue.nTxAnt", 1);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "scenario.ue.nRxAnt", 1);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "run.controlGating.pbchRequired", false);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "run.controlGating.prachRequired", false);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "run.controlGating.pdcchRequired", false);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "run.controlGating.srsRequired", false);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "run.controlGating.trsRequired", false);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "run.controlGating.srsMaxAgeSlots", 0);
cfgCoupled = sixgr.util.structSet(cfgCoupled, "run.controlGating.trsMaxAgeSlots", 0);
cfgCoupled = sixgr.config.normalizeConfig(cfgCoupled);
sixgr.config.validateConfig(cfgCoupled);
cfgCoupled.channel.model = "AWGN";
cfgCoupled.channel.awgnOnly = true;
cfgCoupled.channel.fading.enable = false;
cfgCoupled.phy.pdsch.modulation = "QPSK";
cfgCoupled.phy.pdsch.targetCodeRate = 120/1024;
cfgCoupled.phy.pdsch.codeRate = 120/1024;
runtimeFolder = tempname;
mkdir(runtimeFolder);
runtimeCleanup = onCleanup(@() rmdir(runtimeFolder, "s")); %#ok<NASGU>
multiUser = struct("Enabled", true, "NumUsers", 1, "RNTIStart", 701, ...
    "ExecutionModel", "slot_coupled_truth");
runtime = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfgCoupled, runtimeFolder, multiUser, struct(), 1);
[cfgCoupledUE, runtime] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
    cfgCoupled, runtime, 1, "DL"); %#ok<ASGLU>
coupledResult = sixgr.link.runDLPDSCHThroughput(cfgCoupledUE, ...
    "NumFrames", 1, "SNR_dB", 20, "ExecutionProfile", "phy_calibration");
fprintf("Coupled CSI closure: status=%s trials=%d csirs=%d errors=%d\n", ...
    string(sixgr.util.structGet(coupledResult, "Status", "")), ...
    height(coupledResult.TrialTable), height(coupledResult.CSIRSTrialTable), ...
    height(sixgr.util.structGet(coupledResult, "ErrorTable", table())));
if height(coupledResult.TrialTable) == 1
    fprintf("Coupled trial status=%s crash=%d notes=%s truth=%s failure=%s csi_status=%s csi_error=%s\n", ...
        string(coupledResult.TrialTable.Status(1)), ...
        logical(coupledResult.TrialTable.Crash(1)), ...
        string(coupledResult.TrialTable.Notes(1)), ...
        string(coupledResult.TrialTable.TruthStatus(1)), ...
        string(coupledResult.TrialTable.FailureReason(1)), ...
        string(coupledResult.TrialTable.CSIComputationStatus(1)), ...
        string(coupledResult.TrialTable.CSIComputationErrorIdentifier(1)));
end
assert(height(coupledResult.TrialTable) == 1 && ...
    height(coupledResult.CSIRSTrialTable) == 1, ...
    "Coupled physical-power closure requires one real DL/CSI-RS waveform trial.");
coupledTrial = coupledResult.TrialTable(1,:);
coupledCSI = coupledResult.CSIRSTrialTable(1,:);
expectedCoupledRSRP_dBm = double(row.MeasurementRSRP_dBm) + ...
    double(coupledTrial.AppliedLargeScaleGain_dB);
fprintf("Coupled power closure: measured=%.12g expected=%.12g serving=%.12g gain=%.12g agc=%.12g\n", ...
    double(coupledCSI.MeasurementRSRP_dBm), expectedCoupledRSRP_dBm, ...
    double(coupledTrial.ServingRSRP_dBm), ...
    double(coupledTrial.AppliedLargeScaleGain_dB), ...
    double(coupledTrial.AGCGain_dB));
assert(abs(double(coupledCSI.MeasurementRSRP_dBm) - ...
    expectedCoupledRSRP_dBm) < 0.1, ...
    ["Physical CSI-RSRP must close with the waveform's applied large-scale " + ...
    "gain at the noisy pre-front-end antenna plane within 0.1 dB."]);
assert(abs(double(coupledCSI.MeasurementRSRP_dBm) - ...
    double(coupledTrial.ServingRSRP_dBm)) < 1.0, ...
    ["CSI-RSRP and serving RSRP must use the same per-reference-RE power " + ...
    "plane; a field-scale gap larger than 1 dB indicates broken power lineage."]);
assert(abs(double(coupledCSI.MeasurementRSRP_dBm) - ...
    double(coupledTrial.ServingRSRP_dBm)) < ...
    abs(double(coupledTrial.AGCGain_dB)) - 1, ...
    "The serving/CSI closure must not contain receiver AGC gain.");
assert(strcmpi(string(coupledCSI.TxMeasurementStatus), ...
    "available_exact_waveform_csirs_measurement") && ...
    isfinite(double(coupledCSI.TxMeasurementRSRP_dBm)) && ...
    isfinite(double(coupledCSI.MeasuredReferenceSignalPathloss_dB)), ...
    "The exact transmitted CSI-RS waveform must provide the pathloss reference plane.");
expectedMeasuredPathloss = double(coupledCSI.TxMeasurementRSRP_dBm) - ...
    double(coupledCSI.MeasurementRSRP_dBm);
assert(abs(double(coupledCSI.MeasuredReferenceSignalPathloss_dB) - ...
    expectedMeasuredPathloss) < 1e-10 && ...
    startsWith(string(coupledCSI.PathlossReferenceRS), "CSI-RS-resource-"), ...
    "Measured pathloss must be the exact Tx/Rx CSI-RS reference-RE power difference.");
assert(abs(double(coupledCSI.MeasuredReferenceSignalPathloss_dB) - ...
    double(coupledTrial.AppliedPathloss_dB)) < 1.0, ...
    ["Waveform-measured and geometry-model pathloss must close without " + ...
     "configured-SNR or receiver-gain substitution."]);
ok = true;
end
