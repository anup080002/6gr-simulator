function ok = testSRSPUCCHExactCollisionFDDTDD()
%TESTSRSPUCCHEXACTCOLLISIONFDDTDD Exact shared-UL arbitration in both modes.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
scenarioPaths = [ ...
    fullfile("simulator", "configs", "scenarios", ...
        "lls_causal_access_to_data_wiring.yaml"), ...
    fullfile("simulator", "configs", "scenarios", ...
        "lls_causal_access_to_data_wiring_tdd.yaml")];
expectedDuplex = ["FDD", "TDD"];

for profileIndex = 1:numel(scenarioPaths)
    scenario = sixgr.lls6g.config.loadScenarioConfig( ...
        scenarioPaths(profileIndex));
    cfg = sixgr.config.normalizeConfig( ...
        sixgr.lls6g.buildInternalConfig(scenario, string(tempname)));
    duplex = upper(string(sixgr.phy.frame.resolveDuplexMode(cfg)));
    assert(duplex == expectedDuplex(profileIndex));
    slot = localFindLegalActiveSRSSlot(cfg);

    harqAuthority = sixgr.phy.pucch.resolveConfiguredPRI( ...
        cfg, 1, 101, NaN, "harq");
    csiAuthority = sixgr.phy.pucch.resolveConfiguredPRI( ...
        cfg, 1, 101, NaN, "csi");
    assert(harqAuthority.ResourceId == 0, ...
        "Fixture HARQ authority must select exact configured resource 0.");
    assert(csiAuthority.ResourceId == 10 && ...
        csiAuthority.ResourceSetId == 1, ...
        "CSI authority must derive configured resource set 1/resource 10.");

    row = struct( ...
        "ScheduledAbsoluteSlot", double(slot), ...
        "UEIndex", 1, "RNTI", 101, ...
        "PUCCHResourceId", string(harqAuthority.ResourceId), ...
        "PRIValue", double(harqAuthority.PRIValue), ...
        "PRIProvenance", string(harqAuthority.Source));
    decision = sixgr.phy.frame.resolveSRSPUCCHCollision( ...
        cfg, row, slot, 2);
    assert(decision.Exact && ~decision.ApproximationUsed && ...
        string(decision.DuplexMode) == duplex, ...
        "%s SRS/PUCCH decision was not exact Toolbox evidence.", duplex);
    assert(decision.Collision && decision.OverlapRECount > 0 && ...
        string(decision.Action) == ...
        "defer_srs_preserve_scheduled_pucch", ...
        "%s did not resolve the known cross-UE SRS/PUCCH collision.", duplex);
    assert(decision.SRSUEIndex == 2 && decision.PUCCHUEIndex == 1 && ...
        contains(string(decision.SRSAllocationSource), "nrSRS") && ...
        contains(string(decision.PUCCHAllocationSource), "nrPUCCH"), ...
        "%s decision lost exact source or UE identity.", duplex);
end

ok = true;
fprintf("[PASS] Exact SRS/PUCCH arbitration retained for FDD and TDD.\n");
end

function absoluteSlotOneBased = localFindLegalActiveSRSSlot(cfg)
strictSRS = sixgr.phy.srs.buildSRSConfigFromScenario(cfg);
[probe, ~] = sixgr.phy.grid.makeCarrier(cfg);
slotsPerFrame = 10 * 2^round(log2(double(probe.SubcarrierSpacing) / 15));
duplex = upper(string(sixgr.phy.frame.resolveDuplexMode(cfg)));
for slot0 = 0:(4 * slotsPerFrame - 1)
    legalUL = true;
    if duplex == "TDD"
        partition = sixgr.util.resolveTDDSlotPartition(cfg, slot0);
        legalUL = logical(partition.AllowUL);
    end
    if ~legalUL
        continue;
    end
    [carrier, ~] = sixgr.phy.grid.makeCarrier(cfg, ...
        "Slot", mod(slot0, slotsPerFrame), ...
        "Frame", floor(slot0 / slotsPerFrame));
    if ~isempty(nrSRSIndices(carrier, strictSRS.ToolboxSRS))
        absoluteSlotOneBased = slot0 + 1;
        return;
    end
end
error("sixgr:test:NoLegalActiveSRSOccasion", ...
    "No legal active SRS occasion was found in four frames.");
end
