function ok = testPDSCHDeclaredCoverageMatrix()
%TESTPDSCHDECLAREDCOVERAGEMATRIX Execute every frozen case/test-kind row.

setup6GRSimToolkit("Verbose",false);
root = fullfile(fileparts(mfilename("fullpath")), "vectors", "pdsch");
pairProof = sixgr.pdsch.PDSCHCoverageExecutor.pairCoverageProof(root);
assert(pairProof.GeneratedCaseCount >= 40 ...
    && pairProof.CoveredPairCount == pairProof.RequiredPairCount ...
    && pairProof.MissingPairCount == 0, ...
    "Independent mandatory-domain pairwise generation is incomplete.");
evidence = sixgr.pdsch.PDSCHCoverageExecutor.run( ...
    "VectorRoot",root, ...
    "SeedList",[11 23 47 89], ...
    "ConfidenceLevel",0.95, ...
    "Strict",true, ...
    "RunPairwise",false, ...
    "RunNoNoise",false, ...
    "RunBLER",false, ...
    "TruthAnchorTrials",1);

T = evidence.DeclaredCoverageResults;
required = [ ...
    "CaseID","TestKind","Rank","Modulation","ChannelModel", ...
    "ProductionTXExecuted","ProductionRXExecuted","ExpectedStatus", ...
    "ActualStatus","ErrorIdentifier","Status"];
assert(height(T) == 16*7, ...
    "Every one of the 16 declared cases must execute all seven test kinds.");
assert(all(ismember(required,string(T.Properties.VariableNames))), ...
    "Declared coverage evidence schema is incomplete.");
assert(numel(unique(T.CaseID)) == 16, ...
    "Declared coverage must preserve all 16 frozen case IDs.");
assert(all(groupcounts(categorical(T.TestKind)) == 16), ...
    "Each declared test kind must execute exactly 16 times.");
fullChain = ismember(string(T.TestKind), ...
    ["positive","reserved_re","impairment"]);
noSignal = string(T.TestKind) == "no_signal";
preTXReject = ismember(string(T.TestKind), ...
    ["wrong_rnti","wrong_dmrs","wrong_rv"]);
assert(all(logical(T.ProductionTXExecuted(fullChain))) ...
    && all(logical(T.ProductionRXExecuted(fullChain))), ...
    "Positive, reserved-RE and impairment rows must invoke production TX/RX.");
assert(~any(logical(T.ProductionTXExecuted(noSignal))) ...
    && all(logical(T.ProductionRXExecuted(noSignal))), ...
    "No-signal rows must invoke zero-input RX without generating a waveform.");
assert(~any(logical(T.ProductionTXExecuted(preTXReject))) ...
    && ~any(logical(T.ProductionRXExecuted(preTXReject))), ...
    "Context and RV negatives must be typed rejects before TX and RX.");
assert(all(T.ExecutionBackend(fullChain) == ...
        "canonical_pdsch_tx_channel_rx") ...
    && all(T.ExecutionBackend(noSignal) == ...
        "canonical_receiver_input_validation") ...
    && all(T.ExecutionBackend(T.TestKind == "wrong_rnti") == ...
        "canonical_assignment_validation") ...
    && all(T.ExecutionBackend(T.TestKind == "wrong_dmrs") == ...
        "canonical_dmrs_configuration_validation") ...
    && all(T.ExecutionBackend(T.TestKind == "wrong_rv") == ...
        "canonical_dlsch_coding_plan_validation"), ...
    "Declared execution backends do not match the stages actually executed.");
assert(all(upper(string(T.ExpectedStatus)) == "PASS") ...
    && all(upper(string(T.ActualStatus)) == "PASS") ...
    && all(upper(string(T.Status)) == "PASS"), ...
    "At least one declared production execution failed.");

N = evidence.NegativeTests;
declaredNegativeKinds = [ ...
    "no_signal","wrong_rnti","wrong_dmrs","wrong_rv"];
declaredNegative = ismember(string(N.TestKind),declaredNegativeKinds);
integrationContract = sixgr.pdsch.PDSCHCoverageExecutor. ...
    integrationNegativeContract();
integrationNegative = startsWith(string(N.TestKind),"integration_");
assert(nnz(declaredNegative) == 16*4 ...
        && nnz(integrationNegative) == height(integrationContract) ...
        && height(N) == 16*4 + height(integrationContract), ...
    ["Negative evidence must contain 64 declared receiver/preflight " ...
    "rows plus the exact mandatory integration set."]);
for i = 1:height(integrationContract)
    hit = string(N.TestKind) == integrationContract.TestKind(i);
    assert(nnz(hit) == 1 ...
        && string(N.ExpectedErrorIdentifier(hit)) ...
            == integrationContract.ExpectedErrorIdentifier(i) ...
        && string(N.ActualErrorIdentifier(hit)) ...
            == integrationContract.ExpectedErrorIdentifier(i), ...
        "Missing or mismatched integration negative %s.", ...
        integrationContract.TestKind(i));
end
assert(all(string(N.ExpectedErrorIdentifier) == ...
    string(N.ActualErrorIdentifier)), ...
    "A declared negative produced the wrong typed identifier.");
assert(~any(logical(N.WaveformGenerated)) ...
    && all(upper(string(N.Status)) == "PASS"), ...
    "Negative preflight evidence must fail before waveform generation.");

A = evidence.FadingTruthAnchors;
assert(height(A) == 10*3 ...
    && all(upper(string(A.Status)) == "PASS"), ...
    "Every fading positive/reserved-RE/impairment row needs row-exact truth.");
assert(all(contains(string(A.ChannelEstimateScope), ...
    "resource_selective")) ...
    && ~any(contains(lower(string(A.ChannelEstimateSource)), ...
    ["scalar","fallback","proxy","unit_channel"])), ...
    "Fading anchors must use honest resource-selective channel estimation.");

matrix = readtable(fullfile(root,"pdsch_declared_coverage_matrix.csv"), ...
    "TextType","string","VariableNamingRule","preserve");
fading = matrix(startsWith(matrix.ChannelModel,["TDL-","CDL-"]),:);
truthKinds = ["positive","reserved_re","impairment"];
for i = 1:height(fading)
    for k = 1:numel(truthKinds)
        truthID = "TRUTH-" + fading.CaseID(i) + "-" + truthKinds(k);
        hit = A(A.CaseID == truthID,:);
        assert(height(hit) == 1, ...
            "Missing row-exact fading truth evidence for %s.",truthID);
        assert(hit.ChannelModel == fading.ChannelModel(i) ...
            && hit.Rank == fading.Rank(i) ...
            && hit.Modulation == fading.Modulation(i) ...
            && hit.NumerologyKHz == fading.NumerologyKHz(i) ...
            && hit.MappingType == fading.MappingType(i) ...
            && hit.DMRSConfigurationType == ...
                fading.DMRSConfigurationType(i) ...
            && hit.DMRSLength == fading.DMRSLength(i) ...
            && hit.DMRSAdditionalPosition == ...
                fading.DMRSAdditionalPosition(i) ...
            && hit.DMRSMultiplexing == fading.DMRSMultiplexing(i) ...
            && hit.DMRSPortSet == fading.DMRSPortSet(i) ...
            && hit.PTRSEnabled == logical(fading.PTRSEnabled(i)) ...
            && hit.PrecodingMode == fading.PrecodingMode(i), ...
            "Fading truth evidence does not match declared factors for %s.", ...
            truthID);
        if truthKinds(k) == "reserved_re"
            assert(hit.ReservationApplied ...
                && hit.ReservationReducedG ...
                && hit.ReservedRECount > 0 ...
                && hit.ReservedG < hit.BaselineG, ...
                "Fading reserved-RE truth did not apply a real reduced-G grant.");
        else
            assert(~hit.ReservationApplied, ...
                "Non-reservation fading truth unexpectedly changed the grant.");
        end
    end
end

fprintf(['PDSCH declared coverage: %d executions, %d typed negatives, ' ...
    '%d fading truth anchors\n'],height(T),height(N),height(A));
ok = true;
end
