function ok = testSRSReciprocalMUMIMOPhysicalLeakage()
%TESTSRSRECIPROCALMUMIMOPHYSICALLEAKAGE Bind measured SRS to the true TDD FIR.

setup6GRSimToolkit("Verbose", false);
if exist("nrSRS", "file") ~= 2 || exist("nrCDLChannel", "class") ~= 8
    warning("testSRSReciprocalMUMIMOPhysicalLeakage:Missing5G", ...
        "Required 5G Toolbox APIs are unavailable; skipping physical SRS/MU test.");
    ok = true;
    return;
end

tmpRoot = string(tempname);
mkdir(tmpRoot);
cleanup = onCleanup(@()localRemoveTree(tmpRoot)); %#ok<NASGU>
scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "webgui_sinr_sweep_64x4_mu_mimo_repair_slice.yaml");
scenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scenario, fullfile(tmpRoot, "run"));

multiUser = struct("Enabled", true, "NumUsers", 2, "RNTIStart", 1, ...
    "ExecutionModel", "slot_coupled_truth");
runtime = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfg, fullfile(tmpRoot, "runtime"), multiUser, struct(), 1);
runtime.CurrentServingIdx(1:2) = 1;
runtime.CurrentSlot = 15;
runtime.CurrentFrame = 0;
measurementSNR_dB = 40;
runtime.CurrentSNR_dB = measurementSNR_dB;
out = cell(2, 1);
q = cell(2, 1);
hUL = cell(2, 1);
hDL = cell(2, 1);
cfgDLByUE = cell(2, 1);
for ueIdx = 1:2
    [cfgUL, runtime] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
        cfg, runtime, ueIdx, "UL");
    [runtime, channelState] = ...
        sixgr.truth.CoupledTruthRuntime.acquireRuntimeChannelStateForControl( ...
        runtime, cfgUL, ueIdx, "UL");
    out{ueIdx} = sixgr.link.runSRSChannelEstimation(cfgUL, ...
        "SNR_dB", measurementSNR_dB, "SlotIndex", 15, "TrialIndex", ueIdx, ...
        "ChannelState", channelState);
    assert(logical(out{ueIdx}.SRSRuntimeEvidenceUsable) && ...
        logical(out{ueIdx}.ChannelEstimateAvailable), ...
        "SRS UE %d must produce usable measured channel-estimate evidence.", ueIdx);
    q{ueIdx} = sixgr.phy.mimo.MatrixContract.deserialize( ...
        out{ueIdx}.SpatialSignatureToken, ...
        "ExpectedDigest", out{ueIdx}.SpatialSignatureSHA256);
    assert(isequal(size(q{ueIdx}, 1), 64), ...
        "SRS UE %d must expose the configured 64-element gNB receive domain.", ueIdx);
    channelState = out{ueIdx}.ChannelState;
    assert(isa(channelState.Obj, "sixgr.channel.StaticReciprocalMIMOChannel"), ...
        "SRS UE %d must use the exact static reciprocal CDL endpoint.", ueIdx);
    hUL{ueIdx} = double(channelState.Obj.ImpulseResponse);
    runtime = sixgr.truth.CoupledTruthRuntime.commitRuntimeChannelState( ...
        runtime, channelState);

    % Materialize the opposite endpoint independently through the same
    % production runtime-array path used by PDSCH.  Merely transposing the
    % UL object's FIR cannot detect a direction-specific antenna-metadata,
    % array-orientation, seed, or ChannelFactory construction mismatch.
    [cfgDL, runtime] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
        cfg, runtime, ueIdx, "DL");
    cfgDLByUE{ueIdx} = cfgDL;
    [runtime, dlState] = ...
        sixgr.truth.CoupledTruthRuntime.acquireRuntimeChannelStateForControl( ...
        runtime, cfgDL, ueIdx, "DL");
    userMeta = sixgr.util.structGet(cfgDL, "lls6g.userContext", struct());
    txAntenna = sixgr.util.structGet(userMeta, "RuntimeServingBSAntenna", struct());
    txMeta = sixgr.util.structGet(userMeta, "RuntimeServingBSAntennaMeta", struct());
    rxAntenna = sixgr.util.structGet(userMeta, "RuntimeUEAntenna", struct());
    rxMeta = sixgr.util.structGet(userMeta, "RuntimeUEAntennaMeta", struct());
    sampleRateHz = double(sixgr.util.structGet(out{ueIdx}, ...
        "SampleRate_Hz", sixgr.util.structGet(out{ueIdx}, ...
        "OFDMInfo.SampleRate", 122.88e6)));
    txInfo = struct("OFDM", struct("SampleRate", sampleRateHz));
    dlState = sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
        dlState, cfgDL, complex(zeros(128, 64)), txInfo, ...
        "NumTxAnt", 64, "NumRxAnt", 4, ...
        "TransmitAntennaRuntime", txAntenna, ...
        "ReceiveAntennaRuntime", rxAntenna, ...
        "TransmitAntennaMeta", txMeta, ...
        "ReceiveAntennaMeta", rxMeta);
    assert(isa(dlState.Obj, "sixgr.channel.StaticReciprocalMIMOChannel"), ...
        "DL UE %d must use the exact static reciprocal CDL endpoint.", ueIdx);
    hDL{ueIdx} = double(dlState.Obj.ImpulseResponse);
    expectedDL = permute(hUL{ueIdx}, [1 3 2]);
    reciprocityResidual = norm(hDL{ueIdx}(:) - expectedDL(:)) ./ ...
        max(norm(expectedDL(:)), eps);
    assert(reciprocityResidual <= 1e-12, ...
        ['Independent UL/DL runtime endpoints for UE %d must preserve exact ' ...
         'array-aware TDD reciprocity; relative FIR residual %.6g.'], ...
        ueIdx, reciprocityResidual);
end

design = sixgr.phy.mimo.designMeasuredMUMIMOPair( ...
    q{1}, q{2}, cfg, "DL", 2, 2);
assert(~logical(design.Compatible) && ...
    string(design.Status) == ...
        "designed_pair_victim_leakage_exceeds_configured_threshold" && ...
    any(double(design.MemberLeakage_dB) > ...
        double(design.RequiredLeakageThreshold_dB)), ...
    ['This causal CDL pair is physically infeasible at the configured ' ...
     'joint per-victim leakage threshold and must be rejected before grant ' ...
     'freezing. Status=%s; leakage=[%.6g %.6g] dB (required %.6g); ' ...
     'desired gain=[%.6g %.6g] dB (required %.6g); retained/raw SRS ' ...
     'ranks=[%d/%d %d/%d].'], ...
    char(string(design.Status)), ...
    double(design.MemberLeakage_dB(1)), double(design.MemberLeakage_dB(2)), ...
    double(design.RequiredLeakageThreshold_dB), ...
    double(design.MemberDesiredGain_dB(1)), ...
    double(design.MemberDesiredGain_dB(2)), ...
    double(design.RequiredMinimumDesiredGain_dB), ...
    round(double(out{1}.SpatialSignatureRetainedRank)), ...
    round(double(out{1}.SpatialSignatureRawRank)), ...
    round(double(out{2}.SpatialSignatureRetainedRank)), ...
    round(double(out{2}.SpatialSignatureRawRank)));
p = {double(design.Member1PrecoderPhysical), ...
    double(design.Member2PrecoderPhysical)};
memberLeakage_dB = nan(2, 1);
for victimIdx = 1:2
    peerIdx = 3 - victimIdx;
    desiredPower = localFilteredPowerDL(hDL{victimIdx}, p{victimIdx}, ...
        cfgDLByUE{victimIdx});
    peerPower = localFilteredPowerDL(hDL{victimIdx}, p{peerIdx}, ...
        cfgDLByUE{victimIdx});
    % Evaluate the interference-to-desired ratio at the victim receiver.
    % Comparing one beam at its intended UE with that same beam at the peer
    % can pass while the peer beam still dominates the victim's weaker
    % desired beam, which is exactly the quantity governing MU decode.
    memberLeakage_dB(victimIdx) = 10 * log10(max(peerPower, realmin) / ...
        max(desiredPower, realmin));
end
requiredLeakage_dB = double(design.RequiredLeakageThreshold_dB);
truthQ = cell(2, 1);
for ueIdx = 1:2
    frequencyResponse = fft(hUL{ueIdx}, 1024, 1);
    truthGrid = reshape(frequencyResponse, size(frequencyResponse, 1), 1, ...
        size(frequencyResponse, 2), size(frequencyResponse, 3));
    truthQ{ueIdx} = sixgr.phy.mimo.spatialSignatureFromChannelEstimate( ...
        truthGrid, "Rank", 2, ...
        "SubspaceMode", "complete_detectable_subspace", ...
        "NoiseVariance", 0, "NoiseMargin_dB", 0);
end
truthDesign = sixgr.phy.mimo.designMeasuredMUMIMOPair( ...
    truthQ{1}, truthQ{2}, cfg, "DL", 2, 2);
truthLeakage_dB = [NaN NaN];
if ~isempty(truthDesign.Member1PrecoderPhysical) && ...
        ~isempty(truthDesign.Member2PrecoderPhysical)
    truthP = {double(truthDesign.Member1PrecoderPhysical), ...
        double(truthDesign.Member2PrecoderPhysical)};
    for victimIdx = 1:2
        peerIdx = 3 - victimIdx;
        desiredPower = localFilteredPowerDL(hDL{victimIdx}, ...
            truthP{victimIdx}, cfgDLByUE{victimIdx});
        peerPower = localFilteredPowerDL(hDL{victimIdx}, ...
            truthP{peerIdx}, cfgDLByUE{victimIdx});
        truthLeakage_dB(victimIdx) = 10 * log10(max(peerPower, realmin) / ...
            max(desiredPower, realmin));
    end
end
firLeakageOK = all(isfinite(memberLeakage_dB)) && ...
    all(memberLeakage_dB <= requiredLeakage_dB + 1.0);

% Repeat the isolation measurement with the actual PDSCH OFDM waveform and
% the same power-context scaling used by the shared-slot replay.  This
% catches frozen-matrix expansion and component-specific normalization
% defects that a matrix/FIR energy calculation alone cannot observe.
txWaveform = cell(2, 1);
txInfo = cell(2, 1);
for ueIdx = 1:2
    cfgTx = localPDSCHCalibrationConfig(cfgDLByUE{ueIdx}, design);
    logicalMatrix = double(design.( ...
        "Member" + string(ueIdx) + "PrecoderLogicalPorts"));
    prior = rng;
    restore = onCleanup(@()rng(prior)); %#ok<NASGU>
    rng(7300 + ueIdx, "twister");
    [tx, txInfo{ueIdx}] = sixgr.phy.dl.PDSCH_Tx(cfgTx, ...
        "CompactOutput", true, ...
        "ExecutionProfile", "phy_calibration", ...
        "PrecodingMatrix", logicalMatrix, ...
        "CellCommonSignalOwnershipMode", "reserve_only");
    [txWaveform{ueIdx}, powerContext] = sixgr.rf.applyPowerContext( ...
        tx.Waveform, cfgTx, "DL", txInfo{ueIdx});
    observedDigest = string(sixgr.phy.mimo.MatrixContract.digest( ...
        double(txInfo{ueIdx}.Precoding.MatrixPorts)));
    expectedDigest = string(design.( ...
        "Member" + string(ueIdx) + "MatrixSHA256"));
    assert(size(txWaveform{ueIdx}, 2) == 64, ...
        "UE %d PDSCH produced %d waveform columns instead of 64.", ...
        ueIdx, size(txWaveform{ueIdx}, 2));
    assert(logical(txInfo{ueIdx}.Precoding.HybridElementDomainApplied), ...
        "UE %d PDSCH did not apply hybrid element-domain expansion.", ueIdx);
    assert(observedDigest == expectedDigest, ...
        "UE %d PDSCH matrix digest mismatch: expected %s, observed %s.", ...
        ueIdx, char(expectedDigest), char(observedDigest));
    assert(abs(double(powerContext.PowerClosureError_dB)) <= 1e-9, ...
        "UE %d PDSCH Tx-power closure error is %.12g dB.", ...
        ueIdx, double(powerContext.PowerClosureError_dB));
end
waveformLeakage_dB = nan(2, 1);
for victimIdx = 1:2
    peerIdx = 3 - victimIdx;
    desired = localApplyStaticFIR(hDL{victimIdx}, txWaveform{victimIdx});
    peer = localApplyStaticFIR(hDL{victimIdx}, txWaveform{peerIdx});
    desiredPower = mean(sum(abs(double(desired)).^2, 2));
    peerPower = mean(sum(abs(double(peer)).^2, 2));
    waveformLeakage_dB(victimIdx) = 10 * log10(max(peerPower, realmin) ./ ...
        max(desiredPower, realmin));
end
assert(all(isfinite(waveformLeakage_dB)) && ...
    any(waveformLeakage_dB > requiredLeakage_dB) && ...
    all(abs(waveformLeakage_dB(:) - ...
        double(design.MemberLeakage_dB(:))) <= 1.0) && ...
    all(abs(memberLeakage_dB(:) - ...
        double(design.MemberLeakage_dB(:))) <= 1.0), ...
    ['The rejected measured-SRS design must predict the actual per-victim ' ...
     'PDSCH/FIR leakage within 1 dB and must not be relabeled compatible. ' ...
     'Required %.3f dB; observed ' ...
     '[%.3f %.3f] dB; occupied-band FIR diagnostic=[%.3f %.3f] dB ' ...
     '(pass=%d). Measured-design admission=[%.3f %.3f] dB; exact-FIR ' ...
     'design status=%s, exact-FIR leakage=[%.3f %.3f] dB. ' ...
     'Retained/raw SRS ranks=[%d/%d %d/%d], SRS NMSE=[%.3f %.3f] dB.'], ...
    requiredLeakage_dB, ...
    waveformLeakage_dB(1), waveformLeakage_dB(2), ...
    memberLeakage_dB(1), memberLeakage_dB(2), firLeakageOK, ...
    double(design.MemberLeakage_dB(1)), double(design.MemberLeakage_dB(2)), ...
    char(string(truthDesign.Status)), truthLeakage_dB(1), truthLeakage_dB(2), ...
    round(double(out{1}.SpatialSignatureRetainedRank)), ...
    round(double(out{1}.SpatialSignatureRawRank)), ...
    round(double(out{2}.SpatialSignatureRetainedRank)), ...
    round(double(out{2}.SpatialSignatureRawRank)), ...
    double(out{1}.NMSE_dB), double(out{2}.NMSE_dB));

ok = true;
end

