cfg.run.pdschExecutionProfile = "phy_calibration";
cfg.phy.pdsch.executionProfile = "phy_calibration";
cfg.phy.canonicalGrant = struct("enabled", false);
cfg.mimo.strict = false;
cfg.phy.mimo.strict = false;
cfg.phy.pdsch.nLayers = 2;
cfg.phy.pdsch.numLayers = 2;
cfg.phy.pdsch.NumLayers = 2;
cfg.phy.pdsch.numPorts = double(design.TotalLogicalPorts);
cfg.phy.pdsch.nPorts = double(design.TotalLogicalPorts);
cfg.phy.pdsch.NumAntennaPorts = double(design.TotalLogicalPorts);
cfg.phy.pdsch.modulation = "QPSK";
cfg.phy.pdsch.codeRate = 0.1;
cfg.phy.pdsch.targetCodeRate = 0.1;
cfg.phy.pdsch.mcsTable = "calibration_explicit";
cfg.phy.pdsch.mcsIndex = 0;
cfg.phy.pdsch.normalizePrecodingMatrix = false;
cfg.phy.pdsch.precoding.normalizationConvention = ...
    char(string(design.PrecoderNormalizationConvention));
cfg.phy.pdsch.hybridElementToPortMatrix = ...
    double(design.HybridElementToPortMatrix);
cfg.phy.pdsch.mcsContext = struct( ...
    "UECapability1024QAM", false, ...
    "RRCEnabled1024QAM", false, ...
    "DCIEnabled1024QAM", false, ...
    "DeploymentAllows1024QAM", false, ...
    "FrequencyRangeAllows1024QAM", false, ...
    "BandAllows1024QAM", false, ...
    "FrequencyRange", "FR1", ...
    "OperatingBand", "n78", ...
    "DeploymentClass", "shared_slot_physical_isolation_regression");
end

function powerValue = localFilteredPowerDL(hDL, precoder, cfg)
% Evaluate only the NR occupied subcarriers. Summing raw FIR tap energy is
% an all-Nyquist-band Parseval metric and is not the channel experienced by
% the configured BWP waveform.
hDL = double(hDL);
[carrier, ~] = sixgr.phy.grid.makeCarrier(cfg);
ofdmInfo = nrOFDMInfo(carrier);
nFFT = double(ofdmInfo.Nfft);
nOccupied = 12 * double(carrier.NSizeGrid);
frequencyResponse = fftshift(fft(hDL, nFFT, 1), 1);
firstOccupied = floor((nFFT - nOccupied) / 2) + 1;
occupied = firstOccupied:(firstOccupied + nOccupied - 1);
powerValue = 0;
for frequencyIndex = occupied
    channelMatrix = reshape(frequencyResponse(frequencyIndex, :, :), ...
        size(hDL, 2), size(hDL, 3));
    filtered = channelMatrix * double(precoder);
    powerValue = powerValue + norm(filtered, "fro")^2;
end
powerValue = powerValue ./ max(numel(occupied), 1);
end

function y = localApplyStaticFIR(hDL, x)
hDL = double(hDL);
x = double(x);
y = complex(zeros(size(x, 1), size(hDL, 2)));
for rxIdx = 1:size(hDL, 2)
    for txIdx = 1:size(hDL, 3)
        h = reshape(hDL(:, rxIdx, txIdx), [], 1);
        y(:, rxIdx) = y(:, rxIdx) + filter(h, 1, x(:, txIdx));
    end
end
end

