function tf = localHaveRequired5G()
tf = exist("nrPUSCH", "file") == 2 ...
    && exist("nrPUSCHDecode", "file") == 2 ...
    && exist("nrPUCCH", "file") == 2 ...
    && exist("nrPUCCHDecode", "file") == 2 ...
    && exist("nrSRS", "file") == 2 ...
    && exist("nrChannelEstimate", "file") == 2 ...
    && exist("nrOFDMDemodulate", "file") == 2;
end

function localAssertThrows(fn, expectedId, label)
threw = false;
try
    fn();
catch ME
    threw = contains(string(ME.identifier), string(expectedId));
end
assert(threw, "%s must throw %s.", label, expectedId);
end
