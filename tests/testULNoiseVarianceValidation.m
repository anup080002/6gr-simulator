function localTestResolverRejectsMissingNoiseVariance()
cfg = localBasicPUSCHCfg();
[nVar, status] = sixgr.phy.ul.resolveULNoiseVariance([], cfg, ...
    "ChannelType", "PUSCH", ...
    "OriginalSource", "runtime_metadata");
assert(isnan(nVar) && ~logical(status.IsValid), ...
    "Missing runtime noise variance must stay unavailable.");
assert(strcmpi(char(string(status.Source)), "unavailable_missing"), ...
    "Missing runtime noise variance must report unavailable_missing provenance.");
assert(strcmpi(char(string(status.Status)), "NOT_AVAILABLE"), ...
    "Missing runtime noise variance must remain explicitly unavailable.");
assert(~logical(status.UsedFallback) && ~logical(status.DerivedFromConfig), ...
    "Missing runtime noise variance must not be relabeled as a fallback or configured derivation.");

cfg.run.strictNoiseVarianceRequired = true;
localAssertThrows(@() sixgr.phy.ul.resolveULNoiseVariance([], cfg, ...
    "ChannelType", "PUSCH", ...
    "OriginalSource", "runtime_metadata"), ...
    "sixgr:phy:ul:NoiseVarianceUnavailable", ...
    "Strict UL noise-variance validation");
end

function localTestPUSCHRejectsInvalidNoiseVariance()
cfg = localBasicPUSCHCfg();
[tx, ~] = sixgr.phy.ul.PUSCH_Tx(cfg);

cases = {
    NaN, "unavailable_invalid_nan";
    Inf, "unavailable_invalid_nonfinite";
    -1, "unavailable_invalid_nonpositive";
    0, "unavailable_invalid_nonpositive"
    };

for i = 1:size(cases, 1)
    invalidNoise = cases{i, 1};
    expectedSource = string(cases{i, 2});
    [rx, info] = sixgr.phy.ul.PUSCH_Rx(tx.Waveform, cfg, ...
        "Carrier", tx.Carrier, ...
        "PUSCH", tx.PUSCH, ...
        "PUSCHIndices", tx.PUSCHIndices, ...
        "TransportBlockSize", tx.TransportBlockSize, ...
        "TargetCodeRate", tx.TargetCodeRate, ...
        "RV", tx.RV, ...
        "NoiseVar", invalidNoise);
    assert(~logical(rx.Ok) && ~logical(rx.ReceiverUsable) && ~logical(rx.DecodeAttempted) && ~logical(rx.DecodeUsable), ...
        "Invalid PUSCH noise variance must not proceed as a usable decode.");
    assert(strcmpi(char(string(rx.NoiseVarStatus)), "NOT_AVAILABLE") && strcmpi(char(string(rx.NoiseVarSource)), char(expectedSource)), ...
        "Invalid PUSCH noise variance must preserve the explicit unavailable provenance.");
    assert(isnan(double(rx.NoiseVar)) && strlength(string(rx.FailureReason)) > 0, ...
        "Invalid PUSCH noise variance must stay NaN with an explicit failure reason.");
    assert(isempty(sixgr.util.structGet(rx, "EqualizedSymbolsForEvidence", [])) && isempty(sixgr.util.structGet(rx, "TransportBlock", [])), ...
        "Invalid PUSCH noise variance must not fabricate equalized symbols or a transport block.");
    assert(~logical(sixgr.util.structGet(info, "NoiseVariance", struct("IsValid", false)).IsValid), ...
        "Invalid PUSCH noise variance must surface as unavailable in the receiver info status.");
end

localAssertThrows(@() sixgr.phy.ul.PUSCH_Rx(tx.Waveform, cfg, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "PUSCHIndices", tx.PUSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", NaN, ...
    "StrictNoiseVarianceRequired", true), ...
    "sixgr:phy:ul:NoiseVarianceUnavailable", ...
    "Strict PUSCH invalid-noise validation");
end

function localTestPUSCHAcceptsValidRuntimeNoiseVariance()
cfg = localBasicPUSCHCfg();
[tx, ~] = sixgr.phy.ul.PUSCH_Tx(cfg);
validNoiseVar = 1e-3;
[rx, info] = sixgr.phy.ul.PUSCH_Rx(tx.Waveform, cfg, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "PUSCHIndices", tx.PUSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", validNoiseVar);
assert(logical(rx.ReceiverUsable) && logical(rx.DecodeAttempted) && logical(rx.DecodeUsable), ...
    "Valid runtime PUSCH noise variance must keep the decode path active.");
assert(strcmpi(char(string(rx.NoiseVarStatus)), "OK") && strcmpi(char(string(rx.NoiseVarSource)), "runtime_metadata"), ...
    "Valid runtime PUSCH noise variance must retain runtime_metadata provenance.");
assert(isfinite(double(rx.NoiseVar)) && double(rx.NoiseVar) > 0, ...
    "Valid runtime PUSCH noise variance must remain a positive usable value after domain conversion.");
assert(logical(sixgr.util.structGet(info, "NoiseVariance", struct("IsValid", false)).IsValid), ...
    "Valid runtime PUSCH noise variance must be reported as valid in receiver info.");
end

