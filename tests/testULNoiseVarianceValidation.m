function localTestExplicitControlNoiseVarianceScalesToGridDomain()
tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

cfg = localBasicControlCfg(tmp);
explicitNoiseVar = 1e-6;

fixture = sixgr.phy.pucch.PUCCHFixtureFactory.connected(1, int8(1));
[txPUCCH, ~] = sixgr.phy.ul.PUCCH_Tx(fixture.Carrier, ...
    fixture.Assignment, fixture.Report, "Carrier", fixture.Carrier);
[rxPUCCH, ~] = sixgr.phy.ul.PUCCH_Rx( ...
    txPUCCH.Waveform, fixture.Carrier, fixture.Assignment, fixture.Context, ...
    "Carrier", fixture.Carrier, ...
    "NoiseVariance", explicitNoiseVar, ...
    "NoiseVarianceDomain", "sample");
ofdmInfoPUCCH = nrOFDMInfo(fixture.Carrier);
ofdmInfoPUCCH.NoiseTransform = sixgr.phy.waveform.calibrateOFDMNoiseTransform(fixture.Carrier);
ofdmInfoPUCCH.SampleToGridNoiseVarianceGain = ofdmInfoPUCCH.NoiseTransform.SampleToGridNoiseVarianceGain;
[expectedPUCCHNoiseVar, ~] = sixgr.phy.waveform.convertNoiseVarianceToGridDomain(explicitNoiseVar, ofdmInfoPUCCH, ...
    "InputDomain", "time");
assert(abs(double(rxPUCCH.GridNoiseVariance) - expectedPUCCHNoiseVar) <= ...
    max(1e-12, expectedPUCCHNoiseVar * 1e-9), ...
    "Explicit PUCCH noise variance must be converted into the grid domain before receiver use/export.");

[txSRS, ~] = sixgr.phy.ul.SRS_Tx(cfg);
[rxSRS, ~] = sixgr.phy.ul.SRS_Rx(txSRS.Waveform, cfg, ...
    "Carrier", txSRS.Carrier, ...
    "SRS", txSRS.SRS, ...
    "NoiseVar", explicitNoiseVar);
ofdmInfoSRS = nrOFDMInfo(txSRS.Carrier);
ofdmInfoSRS.NoiseTransform = sixgr.phy.waveform.calibrateOFDMNoiseTransform(txSRS.Carrier);
ofdmInfoSRS.SampleToGridNoiseVarianceGain = ofdmInfoSRS.NoiseTransform.SampleToGridNoiseVarianceGain;
[expectedSRSNoiseVar, ~] = sixgr.phy.waveform.convertNoiseVarianceToGridDomain(explicitNoiseVar, ofdmInfoSRS, ...
    "InputDomain", "time");
assert(strcmpi(char(string(rxSRS.NoiseVarSource)), "runtime_metadata") && ...
    abs(double(rxSRS.NoiseVar) - expectedSRSNoiseVar) <= max(1e-12, expectedSRSNoiseVar * 1e-9), ...
    "Explicit SRS noise variance must be converted into the grid domain before receiver use/export.");
end

function localTestULRunnerExportsNoiseVarianceStatus()
cfgPUSCH = localBasicPUSCHCfg();
res = sixgr.link.runULPUSCHThroughput(cfgPUSCH, "NumFrames", 2, "SNR_dB", 12);
assert(istable(res.TrialTable) && ~isempty(res.TrialTable), ...
    "UL throughput helper must materialize a PUSCH trial table for noise-variance export validation.");
requiredUL = ["NoiseVariance","NoiseVarStatus","NoiseVarSource","NoiseVarReason","NoiseVarStrictFailure", ...
    "ReceiverUsable","DecodeAttempted","DecodeUsable","FailureReason"];
assert(all(ismember(requiredUL, string(res.TrialTable.Properties.VariableNames))), ...
    "UL throughput trial tables must expose the full noise-variance provenance contract.");
assert(~any(abs(double(res.TrialTable.NoiseVariance) - 1e-10) < 1e-18), ...
    "UL throughput trial tables must not export the legacy 1e-10 missing-noise fallback.");
assert(all(strlength(string(res.TrialTable.NoiseVarStatus)) > 0), ...
    "UL throughput trial tables must report a noise-variance status on every row.");

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

cfgControl = localBasicControlCfg(tmp);
fixture = sixgr.phy.pucch.PUCCHFixtureFactory.connected(2, ...
    int8(mod((0:19).', 2)), "RNTI", 320);
trial = sixgr.link.runPUCCHWaveformTrial(fixture.Carrier, ...
    "Assignment", fixture.Assignment, ...
    "Report", fixture.Report, ...
    "ReceiverContext", fixture.Context, ...
    "Carrier", fixture.Carrier, ...
    "SNR_dB", 20, ...
    "Seed", 320);
assert(strcmpi(char(string(trial.NoiseVarStatus)), "OK") && strlength(string(trial.NoiseVarSource)) > 0, ...
    "Waveform-backed PUCCH trials must export explicit valid noise-variance provenance.");
assert(~isfinite(double(trial.NoiseVariance)) || abs(double(trial.NoiseVariance) - 1e-10) > 1e-18, ...
    "Waveform-backed PUCCH trials must not export the legacy 1e-10 missing-noise fallback.");

srs = sixgr.link.runSRSChannelEstimation(cfgControl, "SNR_dB", 20);
assert(strcmpi(char(string(srs.NoiseVarStatus)), "OK") && strlength(string(srs.NoiseVarSource)) > 0, ...
    "Waveform-backed SRS trials must export explicit valid noise-variance provenance.");
assert(~isfinite(double(srs.NoiseVariance)) || abs(double(srs.NoiseVariance) - 1e-10) > 1e-18, ...
    "Waveform-backed SRS trials must not export the legacy 1e-10 missing-noise fallback.");
end

