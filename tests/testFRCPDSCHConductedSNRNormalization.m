function ok = testFRCPDSCHConductedSNRNormalization()
%TESTFRCPDSCHCONDUCTEDSNRNORMALIZATION Guard rank-invariant FRC DL power.

setup6GRSimToolkit("Verbose", false);

if exist("nrPDSCH", "file") ~= 2 || exist("nrPRGInfo", "file") ~= 2
    warning("testFRCPDSCHConductedSNRNormalization:Missing5G", ...
        "Skipping FRC PDSCH conducted-SNR normalization because 5G Toolbox APIs are unavailable.");
    ok = true;
    return;
end

entryIds = [ ...
    "dl_r_pdsch_1_2_1_fdd_tdlc300_100"; ...
    "dl_r_pdsch_1_2_2_fdd_tdla30_10"; ...
    "dl_r_pdsch_1_2_4_fdd_tdla30_10"];
expectedRanks = [1; 2; 4];

rankValue = zeros(numel(entryIds), 1);
numPages = zeros(numel(entryIds), 1);
minTrace = zeros(numel(entryIds), 1);
maxTrace = zeros(numel(entryIds), 1);
maxAbsConductedOffset_dB = zeros(numel(entryIds), 1);

for k = 1:numel(entryIds)
    result = sixgr.conformance.runFRCPoint(entryIds(k), "", ...
        "ValidateSetupOnly", true, ...
        "PrintTable", false, ...
        "Verbose", false);
    evidence = result.SetupValidation.TxEvidence.PrecodingPower;
    traces = double(evidence.PageTraceWWH(:));
    offsets_dB = double(evidence.ConductedSNROffset_dB(:));

    assert(double(evidence.NumLayers) == expectedRanks(k), ...
        "FRC %s resolved rank %g; expected rank %d.", ...
        entryIds(k), double(evidence.NumLayers), expectedRanks(k));
    assert(~logical(evidence.NormalizeW), ...
        ["FRC %s enabled the general column-normalization path, which " ...
        "would restore a rank-dependent conducted-SNR gain."], entryIds(k));
    assert(~isempty(traces) && all(isfinite(traces)), ...
        "FRC %s did not expose finite per-PRG precoder traces.", entryIds(k));
    assert(all(abs(traces - 1) <= 1e-12), ...
        ["FRC %s has trace(W*W') outside the unit-total-power contract: " ...
        "%s."], entryIds(k), mat2str(traces.', 16));
    assert(logical(evidence.AllPagesAtTarget), ...
        "FRC %s did not certify every PRG page at the unit trace target.", ...
        entryIds(k));
    assert(all(isfinite(offsets_dB)) && all(abs(offsets_dB) <= 1e-10), ...
        ["FRC %s has a rank-dependent conducted-SNR power offset: %s dB. " ...
        "TS 38.101-4 clause 4.4.2 excludes precoding gain."], ...
        entryIds(k), mat2str(offsets_dB.', 12));

    rankValue(k) = double(evidence.NumLayers);
    numPages(k) = numel(traces);
    minTrace(k) = min(traces);
    maxTrace(k) = max(traces);
    maxAbsConductedOffset_dB(k) = max(abs(offsets_dB));
end

report = table(entryIds, rankValue, numPages, minTrace, maxTrace, ...
    maxAbsConductedOffset_dB, ...
    'VariableNames', {'FRCEntry', 'Rank', 'PRGPages', ...
    'MinTraceWWH', 'MaxTraceWWH', 'MaxAbsConductedSNROffset_dB'});
disp(report);

assert(isequal(rankValue, expectedRanks), ...
    "The focused FRC power regression must cover ranks 1, 2, and 4.");
fprintf("FRCPDSCHConductedSNRNormalization: rank-1/2/4 unit-total-power contract verified.\n");
ok = true;
end
