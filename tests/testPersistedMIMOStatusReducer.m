function ok = testPersistedMIMOStatusReducer()
%TESTPERSISTEDMIMOSTATUSREDUCER Verify recovery cannot pass vacuously.

setup6GRSimToolkit("Verbose", false);
runFolder = tempname;
mkdir(runFolder);
cleanup = onCleanup(@() localCleanup(runFolder)); %#ok<NASGU>
layout = sixgr.report.resultLayout(runFolder);
sixgr.util.ensureDir(fullfile(layout.BeamformingCSVDir, ".keep"));

cfg = struct();
cfg = sixgr.util.structSet(cfg, "phy.pdsch.numLayers", 2);
cfg = sixgr.util.structSet(cfg, "phy.pusch.numLayers", 2);
status = struct("ConfiguredEffectiveOk", true, ...
    "ConfiguredEffectivePolicyOk", true, "StatusNotes", "");

missing = sixgr.truth.applyPersistedMIMOConfiguredEffectiveStatus( ...
    status, runFolder, cfg);
assert(~missing.ConfiguredEffectiveOk && ...
    ~missing.ConfiguredEffectivePolicyOk && ...
    ~missing.ConfiguredEffectiveSupplementalEvaluated, ...
    "Required MIMO evidence must fail closed when the artifact is absent.");

mimoPath = fullfile(layout.BeamformingCSVDir, ...
    "mimo_configured_vs_effective.csv");
passTable = table(["DL";"UL"], [2;2], [1;1], ...
    [true;true], [true;true], [true;true], [true;true], [true;true], ...
    'VariableNames', {'Direction','StrictEligibleRowCount', ...
    'ExactMatchPercent','SpatialContractMatch', ...
    'FixedOperatingPointMatch','AdaptivePolicyConformance', ...
    'MUExecutionMatch','ScenarioObjectivePass'});
sixgr.util.csvWriteTable(mimoPath, passTable);
passed = sixgr.truth.applyPersistedMIMOConfiguredEffectiveStatus( ...
    status, runFolder, cfg);
assert(passed.ConfiguredEffectiveOk && ...
    passed.ConfiguredEffectivePolicyOk && ...
    passed.ConfiguredEffectiveSupplementalEvaluated, ...
    "Complete passing DL/UL MIMO evidence must preserve an upstream pass.");

failTable = passTable;
failTable.ScenarioObjectivePass(2) = false;
sixgr.util.csvWriteTable(mimoPath, failTable);
failed = sixgr.truth.applyPersistedMIMOConfiguredEffectiveStatus( ...
    status, runFolder, cfg);
assert(failed.ConfiguredEffectiveOk && ...
    ~failed.ConfiguredEffectivePolicyOk && ...
    failed.ConfiguredEffectiveSupplementalEvaluated, ...
    "A policy failure must not corrupt separately proven exact equality.");

adaptiveMismatchTable = passTable;
adaptiveMismatchTable.ExactMatchPercent(:) = 0;
adaptiveMismatchTable.FixedOperatingPointMatch(:) = false;
adaptiveMismatchTable.FixedOperatingPointRequired = false(2, 1);
adaptiveMismatchTable.AdaptivePolicyRequired = true(2, 1);
adaptiveMismatchTable.AdaptiveMode = true(2, 1);
sixgr.util.csvWriteTable(mimoPath, adaptiveMismatchTable);
adaptiveMismatch = sixgr.truth.applyPersistedMIMOConfiguredEffectiveStatus( ...
    status, runFolder, cfg);
assert(~adaptiveMismatch.ConfiguredEffectiveOk && ...
    adaptiveMismatch.ConfiguredEffectivePolicyOk, ...
    "Recovery must preserve exact mismatch separately from adaptive-policy success without requiring a fixed operating point.");
ok = true;
end

function localCleanup(pathStr)
if isfolder(pathStr)
    rmdir(pathStr, "s");
end
end
