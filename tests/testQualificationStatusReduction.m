function testFailedChildCannotProducePassingParent(testCase)
profile=struct();
profile.Preset="comprehensive_smoke";
profile.Components=table("COMP-1","Domain","Component","SC-00", ...
    "true","true","evidence.csv","","requirement","Results", ...
    "FULLSTACK:Component", ...
    'VariableNames',{'ComponentID','Domain','Component','SubcaseID', ...
    'MandatoryInComprehensiveSmoke','MandatoryInDeepAcceptance', ...
    'RequiredCSV','RequiredPNG','CorrectnessRequirement', ...
    'WebGUISection','FailureCode'});
profile.Subcases=table("SC-00","Fixture","Test","both","true", ...
    "1","1","fixture","evidence.csv","","Results", ...
    'VariableNames',{'SubcaseID','Name','Category','Direction', ...
    'Mandatory','ComprehensiveBudgetMinutes','DeepBudgetMinutes', ...
    'Description','RequiredCSV','RequiredPNG','WebGUISection'});
source=table("SC-00",true,'VariableNames',{'SubcaseID','Executed'});
values=table("VAL-1","SC-00",true,"FAIL", ...
    'VariableNames',{'CheckID','SubcaseID','Required','Status'});
negatives=table("NEG-1","SC-00",true,"PASS", ...
    'VariableNames',{'CaseID','SubcaseID','Mandatory','Status'});
audit=table("ART-1","evidence.csv","CSV",true, ...
    string(repmat('a',1,64)),true,true,true,true,"PASS", ...
    'VariableNames',{'ArtifactID','FileName','ArtifactType','Present', ...
    'SHA256','HashValid','SchemaValid','MinimumRowsValid', ...
    'SemanticValid','Status'});
regression=table("SUITE",1,1,1,0,0,0,"PASS", ...
    'VariableNames',{'Suite','MandatoryTests','ExecutedTests', ...
    'PassedTests','FailedTests','SkippedTests','BlockedTests','Status'});
[components,subcases]=sixgr.integration.qualification. ...
    QualificationStatusReducer.reduce(profile,"R",source,values, ...
    negatives,audit,regression);
verifyEqual(testCase,components.Status,"FAIL");
verifyEqual(testCase,subcases.Status,"FAIL");
verifyFalse(testCase,components.CorrectnessChecked);
end

function testAllContractRowsReduceAndMutationPropagates(testCase)
repositoryRoot=fileparts(fileparts(mfilename("fullpath")));
scenario=sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    repositoryRoot,"simulator","configs","scenarios", ...
    "lls_webgui_full_stack_sinr_geometry_qualification.yaml"));
profile=sixgr.integration.qualification. ...
    FullStackQualificationProfile.load(scenario);
source=table(string(profile.Subcases.SubcaseID), ...
    true(height(profile.Subcases),1), ...
    'VariableNames',{'SubcaseID','Executed'});
values=table(string(profile.ValueChecks.CheckID), ...
    string(profile.ValueChecks.SubcaseID), ...
    localTruth(profile.ValueChecks.Required), ...
    repmat("PASS",height(profile.ValueChecks),1), ...
    'VariableNames',{'CheckID','SubcaseID','Required','Status'});
negatives=table(string(profile.NegativeCases.CaseID), ...
    string(profile.NegativeCases.SubcaseID), ...
    localTruth(profile.NegativeCases.Mandatory), ...
    repmat("PASS",height(profile.NegativeCases),1), ...
    'VariableNames',{'CaseID','SubcaseID','Mandatory','Status'});
files=localContractFiles(profile);
audit=table("ART-"+compose("%04d",(1:numel(files))'),files, ...
    repmat("PASS",numel(files),1), ...
    'VariableNames',{'ArtifactID','FileName','Status'});
regression=table("SUITE",1,1,1,0,0,0,"PASS", ...
    'VariableNames',{'Suite','MandatoryTests','ExecutedTests', ...
    'PassedTests','FailedTests','SkippedTests','BlockedTests','Status'});
[components,subcases]=sixgr.integration.qualification. ...
    QualificationStatusReducer.reduce(profile,"R",source,values, ...
    negatives,audit,regression);
verifyEqual(testCase,height(components),163);
verifyEqual(testCase,height(subcases),31);
verifyTrue(testCase,all(components.Status=="PASS"));
verifyTrue(testCase,all(subcases.Status=="PASS"));

mutation=find(values.Required,1);
mutatedSubcase=values.SubcaseID(mutation);
values.Status(mutation)="FAIL";
[components,subcases]=sixgr.integration.qualification. ...
    QualificationStatusReducer.reduce(profile,"R",source,values, ...
    negatives,audit,regression);
verifyTrue(testCase,all(components.Status( ...
    components.SubcaseID==mutatedSubcase)=="FAIL"));
verifyEqual(testCase,subcases.Status( ...
    subcases.SubcaseID==mutatedSubcase),"FAIL");
end

function files=localContractFiles(profile)
values=[string(profile.Subcases.RequiredCSV); ...
    string(profile.Subcases.RequiredPNG); ...
    string(profile.Components.RequiredCSV); ...
    string(profile.Components.RequiredPNG)];
files=strings(0,1);
for value=reshape(values,1,[])
    part=strtrim(split(value,"|"));
    files=[files;part(strlength(part)>0)]; %#ok<AGROW>
end
files=unique(files,"stable");
end

function tf=localTruth(value)
tf=ismember(lower(strtrim(string(value))), ...
    ["true","1","yes","pass","required"]);
end
