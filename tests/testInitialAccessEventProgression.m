function ok=testInitialAccessEventProgression()
% Config/clock/state-boundary regression, not a waveform attach claim.
setup6GRSimToolkit('Verbose',false);
s=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_short.yaml');
cfg=sixgr.lls6g.buildInternalConfig(s,tempname);
assert(cfg.run.numTTI==60);
frame=sixgr.phy.FrameStructureEngine(cfg);
assert(frame.SSBPeriodCarrierSlots==40 && cfg.phy.ssb.periodCarrierSlots==40);
for slot=[1 41 81]
    [active,occasion]=sixgr.truth.isActiveSSBOccasion(cfg,slot);
    assert(active && occasion.PeriodCarrierSlots==40);
    ra=sixgr.mac.ra.RAConfig(cfg,'RuntimeSlot',slot);
    assert(ra.PRACHAbsoluteSlot>=slot-1 && ra.Msg2Slot>ra.PRACHAbsoluteSlot && ...
        ra.Msg3Slot>ra.Msg2Slot && ra.Msg4Slot>ra.Msg3Slot && ...
        ra.SetupCompleteSlot>ra.Msg4Slot);
    assert(ismember(ra.Msg2Slot,ra.RARMonitoringWindow.MonitoringSlots) && ...
        ra.TimingSchedule.RARProcessingDelaySlots==cfg.random_access.timing.rar_processing_delay_slots && ...
        ra.TimingSchedule.Msg4ProcessingDelaySlots==cfg.random_access.timing.msg4_processing_delay_slots && ...
        ra.RAResponseWindowSlots==cfg.random_access.ra_response_window_slots && ...
        ra.PreambleTransMax==cfg.random_access.preamble_trans_max);
    assert(frame.IsULAllocation(ra.Msg3Slot, ...
        [ra.Msg3PUSCH.SymbolStart ra.Msg3PUSCH.NumSymbols]));
end
% Four boundaries, including the previously observed attach slot, must not
% change an unresolved receiver or generate successful/failed trial rows.
state=struct('ControlGating',struct('PBCHRequired',true,'PRACHRequired',true), ...
    'AccessState',["not_attempted";"pending";"succeeded"], ...
    'CellAcquisitionState',["searching";"acquired";"acquired"]);
state.PendingRAAttempts={[];struct('Continuation',struct('NextStage',5));[]};
state.InitialAccessLifecycleTraceTable=table();
for boundary=[35 40 60 100]
    final=sixgr.truth.CoupledTruthRuntime.finalizeFiniteHorizonRuntime(state,boundary,"test_horizon");
    t=final.ControlTrials.RAEvidenceTables.initial_access_horizon;
    assert(isequal(t.UEIndex,[1;2;3]) && ...
        isequal(t.Status,["RIGHT_CENSORED";"RIGHT_CENSORED";"COMPLETED"]) && ...
        isequal(t.RightCensored,[true;true;false]) && ...
        all(t.TerminalRuntimeSlot1Based==boundary));
    assert(t.PendingProcedureStage(1)=="SSB_PBCH_SIB1_reception" && ...
        t.PendingProcedureStage(2)=="RRCSetupComplete" && ...
        ~any(t.RetryLimitExhausted) && all(isnan(t.PendingTimerExpiryTicks)));
    assert(isequal(final.AccessState,state.AccessState) && ...
        isequaln(final.PendingRAAttempts,state.PendingRAAttempts) && ...
        isempty(final.InitialAccessLifecycleTraceTable) && ...
        isequal(fieldnames(final.ControlTrials.RAEvidenceTables),{'initial_access_horizon'}), ...
        'Horizon finalization is an observation, not an access/timer/PHY event.');
    again=sixgr.truth.CoupledTruthRuntime.finalizeFiniteHorizonRuntime(final,boundary,"test_horizon");
    assert(isequaln(t,again.ControlTrials.RAEvidenceTables.initial_access_horizon));
end
disabled=state; disabled.ControlGating.PBCHRequired=false;
disabled.ControlGating.PRACHRequired=false;
assert(isempty(sixgr.truth.initialAccessHorizonEvidence(disabled,60,"test_horizon")));
fprintf('INITIAL_ACCESS_EVENT_PROGRESSION_PASS late_H4_plans=3 horizon_boundaries=4 no_waveform_attach_claim=1\n');
ok=true;
end
