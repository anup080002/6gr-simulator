function ok = testPUCCHMeasuredReferencePowerControl()
%TESTPUCCHMEASUREDREFERENCEPOWERCONTROL Verify shared FDD/TDD PUCCH PC truth.
%
% The configured pathloss is calibration metadata.  Coupled execution must
% use the causally consumed YAML-selected SSB/CSI-RS measurement, preserve
% its identity, and apply TS 38.213 PUCCH power control before the common
% UL RF/channel path.

setup6GRSimToolkit("Verbose",false);
scenarios = ["lls_causal_access_to_data_wiring.yaml", ...
    "lls_causal_access_to_data_wiring_tdd.yaml"];
for scenario = scenarios
    source = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
        "simulator","configs","scenarios",scenario));
    cfg = sixgr.lls6g.buildInternalConfig(source,tempname);
    cfg.lls6g.userContext.RuntimeServingPathloss_dB = 103;
    cfg.lls6g.userContext.RuntimeServingPathlossSource = ...
        "exact_generated_tx_sss_epre_minus_ue_measured_noise_debiased_ss_rsrp";
    cfg.lls6g.userContext.RuntimeServingPathlossReferenceRS = "SSB-0";
    cfg.lls6g.userContext.RuntimeServingPathlossMeasurementId = ...
        "SSB_UE_1_resource_0_slot_4";
    cfg.lls6g.userContext.RuntimeServingPathlossMeasurementSlot = 4;
    cfg.lls6g.userContext.RuntimeServingPathlossReferenceSignalType = "SSB";
    cfg.lls6g.userContext.RuntimeServingPathlossReferenceSignalId = 0;

    connected = sixgr.phy.pucch.PUCCHConfigBuilder.connectedHARQ( ...
        cfg,localUE(cfg),true,localFrame(cfg));
    state = connected.Assignment.PowerControlState.Data;
    resolved = sixgr.phy.pucch.PUCCHPowerController.resolve( ...
        connected.Assignment.PowerControlState);
    assert(double(state.PathlossdB) == 103 && ...
        double(state.ConfiguredPathlossdB) == 77 && ...
        logical(state.RuntimeMeasuredPathlossUsed), ...
        "Scenario %s must replace calibration pathloss with runtime SSB-0 truth.",scenario);
    assert(string(state.PathlossReferenceRS) == "SSB-0" && ...
        string(state.PathlossMeasurementId) == ...
        "SSB_UE_1_resource_0_slot_4" && ...
        contains(string(state.PathlossSource),"exact_generated_tx_sss_epre"), ...
        "Scenario %s must preserve measured pathloss provenance.",scenario);
    expected = -80 + 103;
    assert(abs(double(resolved.RequestedPowerdBm)-expected) < 1e-12 && ...
        abs(double(resolved.AppliedPowerdBm)-23) < 1e-12 && ...
        abs(double(resolved.PowerHeadroomdB)) < 1e-12, ...
        "Scenario %s must apply the exact PUCCH power-control equation.",scenario);

    % Prove the physical UL boundary consumes the typed PUCCH power state,
    % not a stale DL LargeScaleState receive-power value.  This is the
    % same producer path used by connected FDD and TDD waveform trials.
    boundaryCfg = cfg;
    boundaryCfg.lls6g.userContext.RuntimeCurrentDirection = "UL";
    boundaryCfg.lls6g.userContext.Direction = "UL";
    boundaryCfg.lls6g.userContext.RuntimeServingRxPower_dBm = 33.859;
    boundaryCfg.lls6g.userContext.RuntimeServingRxPowerDirection = "DL";
    boundaryCfg.lls6g.userContext.RuntimeServingRxPowerSource = ...
        "LargeScaleState.RxPower_dBm";
    carrier = sixgr.phy.grid.makeCarrier(boundaryCfg);
    tx = sixgr.phy.pucch.PUCCHTransmitter.transmit( ...
        carrier,connected.Assignment,connected.Report);
    [prepared,boundaryCfg,boundary] = ...
        sixgr.link.preparePUCCHTransmitWaveform(tx,boundaryCfg);
    assert(abs(double(boundary.PowerClosureError_dB)) <= 0.05 && ...
        abs(double(boundary.MeasuredTxOutputPower_dBm) - ...
        double(boundary.AppliedPower_dBm)) <= 0.05 && ...
        contains(string(boundary.MeasuredTxOutputPowerReferenceDomain), ...
        "active_nonzero_ofdm_symbols"), ...
        ["Scenario %s PUCCH physical waveform power must close at the " ...
         "active-symbol transmit-power reference plane; inactive slot " ...
         "symbols must not create a false duty-cycle loss."],scenario);
    [~,replay] = sixgr.link.applyWaveformImpairments( ...
        prepared,boundaryCfg,double(tx.OFDMInfo.SampleRate), ...
        "ApplyRFChain",false);
    powerContext = boundary.PowerContext;
    expectedRx = double(boundary.AppliedPower_dBm) + ...
        double(powerContext.TxGain_dB) + double(powerContext.RxGain_dB) - ...
        103 - double(powerContext.AdditionalLoss_dB);
    assert(abs(double(replay.ServingRxPower_dBm)-expectedRx) < 1e-9 && ...
        string(replay.ServingRxPowerSource) == ...
        "signal_specific_power_context_link_budget" && ...
        double(replay.ReferenceTxPower_dBm) == ...
        double(boundary.AppliedPower_dBm), ...
        ["Scenario %s PUCCH receive power must be derived from the exact " ...
         "typed UL transmit power and measured pathloss, never the stale " ...
         "DL receive-power plane."],scenario);

    % Exercise the real coupled-runtime boundary that freezes a future
    % PUCCH resource after a DL decode.  The scenario-level configuration
    % contains calibration pathloss only; the resolver must causally
    % consume the already published SSB-0 measurement for this UE before
    % invoking the strict PUCCH builder.
    tmp = tempname;
    mkdir(tmp);
    cleanup = onCleanup(@() rmdir(tmp,"s")); %#ok<NASGU>
    runtimeCfg = sixgr.lls6g.buildInternalConfig(source,fullfile(tmp,"run"));
    mu = struct("Enabled",false,"NumUsers",1,"RNTIStart", ...
        double(sixgr.util.structGet(runtimeCfg,"phy.rnti",1)), ...
        "ExecutionModel","slot_coupled_truth");
    runtimeState = sixgr.truth.CoupledTruthRuntime.initialize( ...
        runtimeCfg,fullfile(tmp,"runtime"),mu,struct(),1);
    runtimeState.CurrentSlot = 5;
    runtimeState.CurrentServingIdx(1) = 1;
    measured = table(0,103,"SSB-0", ...
        "exact_generated_tx_sss_epre_minus_ue_measured_noise_debiased_ss_rsrp", ...
        'VariableNames',{'ReferenceSignalId', ...
        'MeasuredReferenceSignalPathloss_dB','PathlossReferenceRS', ...
        'MeasuredReferenceSignalPathlossSource'});
    % Explicit analytical selector fixture, not an emitted PHY measurement:
    % cell 1, 0 dBm reference EPRE and -103 dBm RSRP imply 103 dB pathloss.
    % A pathloss-only row must not masquerade as a valid UE observation.
    localAssertIdentifier(@() sixgr.truth.CoupledTruthRuntime. ...
        publishReferenceSignalMeasurementRuntime(runtimeState,"SSB","UE",1,measured, ...
        "ProducerSlot",4,"AvailableSlot",4,"Valid",true,"Direction","DL"), ...
        "MATLAB:expectedFinite");
    measured.ServingCell=1;
    measured.SS_RSRP_dBm=-103;
    measured.ReferenceSignalTxEPRE_dBm=0;
    runtimeState = sixgr.truth.CoupledTruthRuntime. ...
        publishReferenceSignalMeasurementRuntime(runtimeState,"SSB","UE",1,measured, ...
        "ProducerSlot",4,"AvailableSlot",4,"Valid",true, ...
        "Direction","DL","SourceSignal","SSB", ...
        "MeasurementSource","same_waveform_pbch_rx_sss_measurement");
    identity = sixgr.util.structGet(runtimeCfg,"phy.frame.DefaultIdentity",struct());
    feedback = struct("UEIndex",1,"RNTI",double(sixgr.util.structGet(runtimeCfg,"phy.rnti",1)), ...
        "ServingCell",1,"SourceSlot",1,"DueSlot",5,"Ack",true, ...
        "ComponentCarrier",double(sixgr.util.structGet(identity,"ScheduledCCID",0)), ...
        "ActiveULBWP",double(sixgr.util.structGet(identity,"ULBWPID",0)));
    causalResource = sixgr.truth.CoupledTruthRuntime. ...
        resolvePUCCHResourceAssignmentRuntime(runtimeState,feedback);
    assert(logical(causalResource.ControlResourceValidity) && ...
        strlength(string(causalResource.ResourceId)) > 0, ...
        "Scenario %s must freeze PUCCH using the causal UE measurement context.",scenario);

    % Periodic SS/PBCH occasions remain serving-beam/pathloss measurement
    % producers after acquisition.  Refresh the exact SSB-0 observation at
    % slot 21 and prove a slot-25 PUCCH does not use the stale slot-4 sample
    % or the configured calibration pathloss.  A missed later tracking
    % occasion must not erase the already acquired MIB state.
    runtimeState.CellAcquisitionState(1) = "acquired";
    runtimeState.CurrentSlot = 21;
    tracking = table(21,"PASS",true,0,-103,103,"SSB-0", ...
        "exact_generated_tx_sss_epre_minus_ue_measured_noise_debiased_ss_rsrp", ...
        true,0,1,-103,"same_waveform_sss_beam_selection", ...
        'VariableNames',{'Slot','Status','CRCPass','ReferenceSignalId', ...
        'SS_RSRP_dBm','MeasuredReferenceSignalPathloss_dB', ...
        'PathlossReferenceRS','MeasuredReferenceSignalPathlossSource', ...
        'SelectedBeamFlag','SelectedSSBIndex','SelectedBeamIndex', ...
        'SelectionMetricValue_dB','SelectionSource'});
    tracking.ServingCell=1;
    tracking.ReferenceSignalTxEPRE_dBm=0;
    runtimeState = sixgr.truth.CoupledTruthRuntime. ...
        applyServingSSBTrackingTrial(runtimeState,1,tracking);
    refreshed = sixgr.truth.CoupledTruthRuntime. ...
        consumeReferenceSignalPathlossRuntime( ...
        runtimeState,"SSB","UE",1,25,20,0);
    assert(logical(refreshed.Usable) && double(refreshed.ProducerSlot)==21 && ...
        string(refreshed.MeasurementId)=="SSB_UE_1_resource_0_slot_21", ...
        "Scenario %s must refresh SSB-0 power-control evidence on the periodic occasion.",scenario);
    runtimeState.CurrentSlot = 25;
    feedback.SourceSlot = 21;
    feedback.DueSlot = 25;
    refreshedResource = sixgr.truth.CoupledTruthRuntime. ...
        resolvePUCCHResourceAssignmentRuntime(runtimeState,feedback);
    assert(logical(refreshedResource.ControlResourceValidity), ...
        "Scenario %s must resolve late PUCCH from refreshed serving-SSB evidence.",scenario);
    missed = tracking;
    missed.Slot(:) = 41;
    missed.Status(:) = "FAIL";
    missed.CRCPass(:) = false;
    runtimeState.CurrentSlot = 41;
    runtimeState = sixgr.truth.CoupledTruthRuntime. ...
        applyServingSSBTrackingTrial(runtimeState,1,missed);
    assert(runtimeState.CellAcquisitionState(1)=="acquired" && ...
        runtimeState.SSBTrackingFailureCountByUE(1)==1, ...
        "Scenario %s must not revoke PBCH acquisition after a missed tracking burst.",scenario);

    mismatched = cfg;
    mismatched.lls6g.userContext.RuntimeServingPathlossReferenceSignalId = 1;
    localAssertIdentifier(@() sixgr.phy.pucch.PUCCHConfigBuilder. ...
        connectedHARQ(mismatched,localUE(mismatched),true,localFrame(mismatched)), ...
        "sixgr:phy:pucch:PathlossReferenceIdentityMismatch");

    missing = cfg;
    missing.lls6g.userContext.RuntimeServingPathlossMeasurementId = "";
    localAssertIdentifier(@() sixgr.phy.pucch.PUCCHConfigBuilder. ...
        connectedHARQ(missing,localUE(missing),true,localFrame(missing)), ...
        "sixgr:phy:pucch:PathlossReferenceSignalMeasurementMissing");
end
ok = true;
fprintf("[PASS] testPUCCHMeasuredReferencePowerControl FDD/TDD measured SSB-0 authority.\n");
end

function ue = localUE(cfg)
identity = sixgr.util.structGet(cfg,"phy.frame.DefaultIdentity",struct());
ue = struct("UEID",1,"RNTI",double(sixgr.util.structGet(cfg,"phy.rnti",1)), ...
    "ServingCell",1,"PUCCHCell",1, ...
    "ComponentCarrier",double(sixgr.util.structGet(identity,"ScheduledCCID",0)), ...
    "ActiveULBWP",double(sixgr.util.structGet(identity,"ULBWPID",0)));
end

function frame = localFrame(cfg)
mode = upper(string(sixgr.util.structGet(cfg,"phy.duplex.mode","FDD")));
ownership = "UUUUUUUUUUUUUU";
if mode == "TDD"
    % Target slot is selected as a configured full-UL slot; resource-level
    % validation still owns the final symbol allocation.
    ownership = "UUUUUUUUUUUUUU";
end
frame = struct("K1",4,"K1Source","decoded_dci", ...
    "PDSCHEndSlot",1,"TargetSlot",5,"DecodedPRI",0, ...
    "PRIFieldWidth",3,"PRIProvenance","focused_runtime_measurement", ...
    "FirstCCE",0,"NumCCE",4,"SlotSymbolOwnership",ownership, ...
    "FlexibleResolutionProvided",false, ...
    "TriggeringEventID","focused-pucch-power-control");
end

function localAssertIdentifier(fn,expected)
try
    fn();
catch ME
    assert(string(ME.identifier)==string(expected), ...
        "Expected %s, received %s: %s",expected,ME.identifier,ME.message);
    return;
end
error("sixgr:test:ExpectedErrorNotRaised", ...
    "Expected error %s was not raised.",expected);
end
