function ok = testCausalFeedbackAMC()
%TESTCAUSALFEEDBACKAMC Verify calibrated causal CSI/AMC contracts.

setup6GRSimToolkit("Verbose", false);

cfg = sixgr.config.defaultConfig();
cfg.phy.nRxAnt = 2;
cfg.phy.nTxAnt = 2;
cfg = sixgr.util.structSet(cfg, "phy.csi.maxRank", 2);
cfg = sixgr.util.structSet(cfg, "phy.csi.pmiCodebookMode", "noncodebook");

[csi, info] = sixgr.phy.dl.CSI_Feedback(eye(2), 0.01, cfg, "MaxRank", 2);
assert(double(csi.RI) == 2, ...
    "DL CSI must select rank from the MI-scored receiver objective, not an SVD-gap clamp.");
assert(string(csi.RankSelectionMethod) == "wideband_codebook_post_equalization_mi" && ...
    string(info.RankSelectionObjective) == "sum_log2_one_plus_layer_sinr", ...
    "DL CSI must disclose the rank objective used for PMI/RI selection.");
assert(all(isfinite(double(csi.SelectedLayerSINR_dB(:)))) && ...
    isfinite(double(csi.SelectedMutualInformation_bpcu)), ...
    "DL CSI must expose finite selected-layer SINR and MI diagnostics.");

cfgUL = cfg;
cfgUL = sixgr.util.structSet(cfgUL, "phy.pusch.transmissionScheme", "codebook");
cfgUL = sixgr.util.structSet(cfgUL, "phy.pusch.transformPrecoding", false);
cfgUL = sixgr.util.structSet(cfgUL, "phy.pusch.maxRankDefault", 2);
cfgUL = sixgr.util.structSet(cfgUL, "phy.pusch.NumAntennaPorts", 2);
cfgUL = sixgr.util.structSet(cfgUL, "phy.pusch.numAntennaPorts", 2);
Hest = repmat(reshape(eye(2), 1, 1, 2, 2), [24, 2, 1, 1]);
est = sixgr.phy.ul.estimateSRSRITPMI(Hest, 0.01, cfgUL);
assert(logical(est.Valid) && double(est.RI) == 2, ...
    "UL SRS RI must come from the post-equalization MI objective for a full-rank channel.");
assert(contains(string(est.RISource), "post_equalization_mi") && ...
    isfinite(double(est.RankMutualInformation)), ...
    "UL SRS RI provenance and MI score must be exported.");

cfgAMC = sixgr.config.defaultConfig();
cfgAMC = sixgr.util.structSet(cfgAMC, "phy.linkAdaptation.mode", "amc");
cfgAMC = sixgr.util.structSet(cfgAMC, "phy.linkAdaptation.dlPolicy", "baseline");
cfgAMC = sixgr.util.structSet(cfgAMC, "phy.linkAdaptation.domain", "effective_sinr");
cfgAMC = sixgr.util.structSet(cfgAMC, "phy.linkAdaptation.outerLoopFlag", false);
cfgAMC = sixgr.util.structSet(cfgAMC, "phy.linkAdaptation.maxCSIAgingPenalty_dB", 6);
cfgAMC = sixgr.util.structSet(cfgAMC, "channel.doppler_Hz", 500);
cfgAMC = sixgr.util.structSet(cfgAMC, "phy.numerology.slotDuration_ms", 1);
metrics = struct( ...
    "SINR_dB", 18, ...
    "SINRSource", "post_equalization_sinr_from_equalizer", ...
    "SINRValueRole", "measured_post_equalization_scheduling_input", ...
    "SINRValueStatus", "OK", ...
    "RI", 1, ...
    "CombinedDecodeOK", true);
[fresh, ~] = sixgr.link.computeLinkAdaptationDecision(cfgAMC, "DL", metrics);
metrics.CSIAgeSlots = 10;
[aged, ~] = sixgr.link.computeLinkAdaptationDecision(cfgAMC, "DL", metrics);
assert(logical(fresh.Valid) && logical(aged.Valid), ...
    "Fresh and aged measured SINR decisions must both produce valid AMC decisions.");
assert(double(aged.MCSIndex) <= double(fresh.MCSIndex) && ...
    double(aged.FeedbackAgingPenalty_dB) > 0 && ...
    double(aged.AgedSINR_dB) < double(fresh.AgedSINR_dB), ...
    "CSI aging must reduce the SINR/CQI operating point before MCS selection.");
assert(contains(string(aged.CalibrationProfile), "target_bler") && ...
    string(aged.CalibrationVersion) == "nr_cqi_mcs_table_v1", ...
    "AMC decisions must carry versioned calibration and target-BLER metadata.");

cfgCQIAging = sixgr.util.structSet(cfgAMC, "phy.linkAdaptation.domain", "cqi");
metricsCQIFresh = struct("CQI", 12, "RI", 1, "CSIAgeSlots", 0);
metricsCQIAged = metricsCQIFresh;
metricsCQIAged.CSIAgeSlots = 10;
[freshCQI, ~] = sixgr.link.computeLinkAdaptationDecision(cfgCQIAging, "DL", metricsCQIFresh);
[agedCQI, ~] = sixgr.link.computeLinkAdaptationDecision(cfgCQIAging, "DL", metricsCQIAged);
assert(logical(freshCQI.Valid) && logical(agedCQI.Valid) && ...
    double(agedCQI.ResolvedCQI) < double(freshCQI.ResolvedCQI) && ...
    double(agedCQI.MCSIndex) <= double(freshCQI.MCSIndex) && ...
    double(agedCQI.FeedbackAgingPenalty_dB) > 0, ...
    "Delayed reported CQI must be aged by default before scheduler-facing MCS selection.");

cfgCQI = sixgr.util.structSet(cfgAMC, "phy.linkAdaptation.domain", "cqi");
cfgCQI = sixgr.util.structSet(cfgCQI, "phy.linkAdaptation.innerLoopFlag", true);
cfgCQI = sixgr.util.structSet(cfgCQI, "phy.linkAdaptation.cqiSmoothingMode", "fixed");
cfgCQI = sixgr.util.structSet(cfgCQI, "phy.linkAdaptation.cqiSmoothingAlpha", 0.5);
cfgCQI = sixgr.util.structSet(cfgCQI, ...
    "phy.linkAdaptation.outageRecoveryPositiveCQIReports", 2);
cfgCQI = sixgr.util.structSet(cfgCQI, ...
    "phy.linkAdaptation.outageRecoveryCQITolerance", 1);
cfgCQI = sixgr.util.structSet(cfgCQI, ...
    "phy.linkAdaptation.outageRecoveryMaxGapSlots", 5);
cfgCQI = sixgr.util.structSet(cfgCQI, "channel.doppler_Hz", 0);
cfgCQI = sixgr.util.structSet(cfgCQI, "phy.pdsch.mcsIndex", 4);
blocked = sixgr.link.computeLinkAdaptationDecision(cfgCQI, "DL", ...
    struct("CQI", 12, "RI", 1, "CausalFeedbackUsable", false));
assert(~logical(blocked.Valid) && string(blocked.Reason) == "stale_or_unusable_csi_feedback", ...
    "Unusable causal feedback must fail closed instead of consuming a stale CQI.");

stateBeforeCQI0 = struct();
[outOfRange, stateAfterCQI0] = sixgr.link.computeLinkAdaptationDecision(cfgCQI, "DL", ...
    struct("CQI", 0, "RI", 1, "CombinedDecodeOK", false, ...
        "FeedbackAbsoluteSlot", 24), ...
    "AdaptationState", stateBeforeCQI0);
assert(~logical(outOfRange.Valid) && ...
    string(outOfRange.Reason) == "measured_cqi_zero_out_of_range" && ...
    string(outOfRange.MCSValueStatus) == "unavailable_measured_cqi_zero_out_of_range" && ...
    double(stateAfterCQI0.UpdateCount) == 0 && ...
    double(stateAfterCQI0.CQIObservationCount) == 1 && ...
    double(stateAfterCQI0.CQIOutageObservationCount) == 1 && ...
    logical(stateAfterCQI0.LastCQIOutOfRange), ...
    "CQI 0 must block transmission while remaining a real ILLA temporal observation.");

% The first positive CQI after a measured outage may be carried without a
% UCI CRC.  It must therefore recover through the configured causal ILLA
% filter rather than initialize directly at its raw MCS.
[recoveryPending, stateRecoveryPending] = sixgr.link.computeLinkAdaptationDecision( ...
    cfgCQI, "DL", struct("CQI", 13, "RI", 1, "FeedbackAbsoluteSlot", 29), ...
    "AdaptationState", stateAfterCQI0);
assert(~logical(recoveryPending.Valid) && ...
    logical(recoveryPending.CQIOutageRecoveryFilterApplied) && ...
    logical(recoveryPending.CQIOutageRecoveryPending) && ...
    double(recoveryPending.ResolvedCQI) == 6 && ...
    double(recoveryPending.CQIOutageRecoveryPositiveCount) == 1 && ...
    double(recoveryPending.CQIOutageRecoveryRequiredCount) == 2 && ...
    string(recoveryPending.MCSSelectionSource) == "blocked_cqi_outage_recovery_filter" && ...
    ~isfinite(double(recoveryPending.MCSIndex)) && ...
    double(stateRecoveryPending.OLLAUpdateCount) == 0, ...
    "A single large positive CQI after outage must not create a high-MCS grant.");

[recovered, stateRecovered] = sixgr.link.computeLinkAdaptationDecision( ...
    cfgCQI, "DL", struct("CQI", 13, "RI", 1, "FeedbackAbsoluteSlot", 34), ...
    "AdaptationState", stateRecoveryPending);
[~, ~, rawCQI13MCS] = sixgr.link.amcFromCQI(13, "", NaN, cfgCQI, "DL");
assert(logical(recovered.Valid) && ...
    logical(recovered.CQIOutageRecoveryFilterApplied) && ...
    ~logical(recovered.CQIOutageRecoveryPending) && ...
    double(recovered.ResolvedCQI) == 9 && ...
    double(recovered.CQIOutageRecoveryPositiveCount) == 2 && ...
    double(recovered.MCSIndex) < double(rawCQI13MCS) && ...
    double(stateRecovered.CQIObservationCount) == 3 && ...
    double(stateRecovered.OLLAUpdateCount) == 0 && ...
    ~logical(stateRecovered.LastCQIOutOfRange), ...
    "Repeated positive CQI must leave outage conservatively without using transmitted bits or configured SNR.");

% Reproduce the retained-run sequence. A lone decoded CQI 10 followed by a
% CQI 13 after missed periodic occasions is not a consistent recovery pair.
[~, poisonState0] = sixgr.link.computeLinkAdaptationDecision(cfgCQI, "DL", ...
    struct("CQI", 0, "RI", 1, "FeedbackAbsoluteSlot", 24));
[poisonFirst, poisonState1] = sixgr.link.computeLinkAdaptationDecision(cfgCQI, "DL", ...
    struct("CQI", 10, "RI", 1, "FeedbackAbsoluteSlot", 29), ...
    "AdaptationState", poisonState0);
[poisonGap, poisonState2] = sixgr.link.computeLinkAdaptationDecision(cfgCQI, "DL", ...
    struct("CQI", 13, "RI", 1, "FeedbackAbsoluteSlot", 44), ...
    "AdaptationState", poisonState1);
assert(~logical(poisonFirst.Valid) && ~logical(poisonGap.Valid) && ...
    double(poisonGap.CQIOutageRecoveryFeedbackGapSlots) == 15 && ...
    double(poisonGap.CQIOutageRecoveryCandidate) == 13 && ...
    double(poisonGap.CQIOutageRecoveryPositiveCount) == 1 && ...
    logical(poisonState2.LastCQIOutOfRange), ...
    "Missed periodic reports must break outage-recovery confirmation instead of authorizing an optimistic grant.");
[poisonRecovered, ~] = sixgr.link.computeLinkAdaptationDecision(cfgCQI, "DL", ...
    struct("CQI", 13, "RI", 1, "FeedbackAbsoluteSlot", 49), ...
    "AdaptationState", poisonState2);
assert(logical(poisonRecovered.Valid) && ...
    double(poisonRecovered.CQIOutageRecoveryPositiveCount) == 2 && ...
    double(poisonRecovered.CQIOutageRecoveryFeedbackGapSlots) == 5, ...
    "Two timely, mutually consistent receiver-decoded CQIs must permit conservative recovery.");

cfgSched = cfgCQI;
cfgSched = sixgr.util.structSet(cfgSched, "phy.linkAdaptation.bootstrapCQIMode", "measured_only");
cfgSched = sixgr.util.structSet(cfgSched, "phy.linkAdaptation.maxCSIAgeSlots", 4);
scheduler = sixgr.l2.mac.SchedulerPF(cfgSched, "Direction", "DL");
[~, ~, ~, amc] = scheduler.selectAMC(struct("RNTI", 7001, "CQI", 11, "CSIAgeSlots", 8));
assert(~logical(amc.CausalFeedbackUsable) && ...
    string(amc.MCSSelectionSource) == "blocked_missing_runtime_cqi" && ...
    contains(string(amc.CausalFeedbackStatus), "stale_csi"), ...
    "Scheduler AMC must reject CQI feedback older than the configured causal age limit.");

ok = true;
end
