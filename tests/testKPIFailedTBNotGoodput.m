function ok = testKPIFailedTBNotGoodput()
%TESTKPIFAILEDTBNOTGOODPUT Failed CRC TBs count as load, not delivered goodput.

setup6GRSimToolkit("Verbose", false);

raw = struct();
raw.UL = table( ...
    repmat("UL", 2, 1), [0; 0], [false; false], [10; 20], [1000; 1000], ...
    [1000; 1000], [1000; 1000], [1; 1], [1; 2], ["ul_fail_1"; "ul_fail_2"], ...
    [0; 0], [0; 0], [0; 1], [1; 1], [1; 2], ...
    'VariableNames', {'Direction','Goodput_Mbps','CRCPass','BitErrors','BitsCompared', ...
    'TBSize_bits','GoodBits','Frame','Slot','TransportBlockId','HARQProcessId','RV','NDI', ...
    'AirInterfaceObservation_ms','TrialId'});
raw.DL = localDirectionTable("DL", 1);

out = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw, "StrictMode", true);
ulGoodput = out.ReconstructionSummary(strcmp(string(out.ReconstructionSummary.KPIName), ...
    "UL_TB_Delivery_Goodput_Mbps"), :);
ulSched = out.ReconstructionSummary(strcmp(string(out.ReconstructionSummary.KPIName), ...
    "UL_PHY_ScheduledThroughput_Mbps"), :);
ulBler = out.ReconstructionSummary(strcmp(string(out.ReconstructionSummary.KPIName), "UL_BLER"), :);
assert(double(ulGoodput.NumeratorValue(1)) == 0 && double(ulGoodput.ReconstructionValue(1)) == 0, ...
    "Failed TBs must contribute zero delivered goodput bits.");
assert(double(ulSched.NumeratorValue(1)) == 2000, ...
    "Failed TBs must still contribute scheduled/load bits.");
assert(abs(double(ulBler.ReconstructionValue(1)) - 1) < 1e-12, ...
    "All-failed TB fixture must reconstruct BLER=1.");

ok = true;
end

function T = localDirectionTable(direction, goodput)
T = table( ...
    repmat(string(direction), 1, 1), goodput, true, 0, 1000, ...
    1000, 1000, 1, 1, string(direction + "_tb_1"), 0, 0, 0, 1, 1, ...
    'VariableNames', {'Direction','Goodput_Mbps','CRCPass','BitErrors','BitsCompared', ...
    'TBSize_bits','GoodBits','Frame','Slot','TransportBlockId','HARQProcessId','RV','NDI', ...
    'AirInterfaceObservation_ms','TrialId'});
end
