function ok = testLLSBundleRuntimeEvidenceExports()
%TESTLLSBUNDLERUNTIMEEVIDENCEEXPORTS Ensure the active LLS bundle preserves antenna and ToD/ToA evidence into raw trial CSVs.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scfg = sixgr.lls6g.config.loadScenarioConfig( ...
    fullfile(pwd, "simulator", "configs", "scenarios", "lls_100mhz_tdlc_bidirectional_truth.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
cfg.run.runTag = "focused_runtime_identity";
cfg.run.scenarioID = char(string(scfg.ScenarioID));
cfg.run.executionID = "execution-focused-runtime-identity";
cfg.meta.scenarioID = char(string(scfg.ScenarioID));
cfg.meta.executionID = cfg.run.executionID;
cfg.meta.configHash = char(string(scfg.ConfigHash));
% Five canonical slots are the minimal real TDD slice that reaches the
% K2=4 UL grant scheduled from DL slot 1: D,D,D,U,U.  This retains real
% DL/CSI-RS and UL/PUSCH execution while keeping the dedicated gate fast.
slotBudget = 5;
cfg.run.numFrames = slotBudget;
cfg.scenario.nUE = 1;
cfg.scenario.ue.nUE = 1;
cfg = sixgr.util.structSet(cfg, "lls6g.users.n_users", 1);
cfg = sixgr.util.structSet(cfg, "lls6g.users.enabled", true);
cfg = sixgr.util.structSet(cfg, "lls6g.users.execution_model", "slot_coupled_truth");
cfg = sixgr.util.structSet(cfg, "users.n_users", 1);
cfg = sixgr.util.structSet(cfg, "deployment_topology.num_ues", 1);
cfg = sixgr.util.structSet(cfg, "run.strictMode", false);
cfg = sixgr.util.structSet(cfg, "run.noProxyTruthContract", false);
cfg.channel.model = "TDL";
cfg.channel.tdlProfile = "TDL-C";
cfg.channel.awgnOnly = false;
cfg.channel.snr_dB = 18;
cfg.run.interferenceExecutionMode = "full_per_link_channel_waveform_sum";
cfg.phy.csirs.enable = true;
cfg.phy.csirs.nPorts = 1;
cfg.phy.csirs.rowNumber = 1;
slotDuration_s = max(eps, double(sixgr.util.structGet(cfg, "phy.numerology.slotDuration_ms", 1)) / 1e3);

runFolder = fullfile(tmp, "bundle", "air_interface");
opt = struct( ...
    "LinkDuration_s", slotBudget * slotDuration_s, ...
    "LinkMaxSimFrames", slotBudget, ...
    "LinkSNR_dB", cfg.channel.snr_dB, ...
    "LinkSNRGrid_dB", cfg.channel.snr_dB, ...
    "LinkSweepFrames", slotBudget, ...
    "LinkSweepTrialsPerSNR", slotBudget, ...
    "LinkReferenceSweepFrames", slotBudget, ...
    "LinkSweepMaxPoints", 1, ...
    "SaveFigures", false);
out = sixgr.truth.runWaveformLinkBundle(cfg, runFolder, opt);
localAssertBoundControlIdentity(out, cfg);

dlCsv = fullfile(runFolder, "csv", "dl_pdsch_trials.csv");
ulCsv = fullfile(runFolder, "csv", "ul_pusch_trials.csv");
csirsCsv = fullfile(runFolder, "csv", "csi_rs_trials.csv");
csiReportCsv = fullfile(tmp, "bundle", "air_interface", "csv", "csi_feedback_reports.csv");
referenceMeasurementCsv = fullfile(tmp, "bundle", "reports", "csv", "reference_signal_measurements.csv");
liveChannelStateCsv = fullfile(tmp, "bundle", "reports", "csv", "live_channel_state_tti.csv");
assert(exist(dlCsv, "file") == 2 && exist(ulCsv, "file") == 2, ...
    "Waveform bundle must write the canonical raw DL/UL trial CSVs.");
assert(exist(csirsCsv, "file") == 2, ...
    "Waveform bundle must persist the dedicated runtime CSI-RS trial stream when CSI-RS is active.");
assert(exist(csiReportCsv, "file") == 2 && exist(referenceMeasurementCsv, "file") == 2, ...
    "Waveform bundle must persist causal CSI feedback delivery and reference-signal measurement ledgers.");
assert(exist(liveChannelStateCsv, "file") == 2, ...
    "Waveform bundle must persist the receiver channel-state projection.");

dlT = readtable(dlCsv, "VariableNamingRule", "preserve", "Delimiter", ",");
ulT = readtable(ulCsv, "VariableNamingRule", "preserve", "Delimiter", ",");
csirsT = readtable(csirsCsv, "VariableNamingRule", "preserve", "Delimiter", ",");
csiReportT = readtable(csiReportCsv, "VariableNamingRule", "preserve", "Delimiter", ",");
referenceMeasurementT = readtable(referenceMeasurementCsv, "VariableNamingRule", "preserve", "Delimiter", ",");
liveChannelStateT = readtable(liveChannelStateCsv, "VariableNamingRule", "preserve", "Delimiter", ",");
localAssertBundleEvidence(dlT, "DL", true);
localAssertBundleEvidence(ulT, "UL", false);
localAssertBundleCSIRSEvidence(csirsT);
assert(~isempty(csiReportT) && all(ismember({'SourceSlot','DueSlot','DeliveredSlot','Processed','ReportIdentity','DeliveryStatus'}, ...
    csiReportT.Properties.VariableNames)) && all(double(csiReportT.DueSlot) >= double(csiReportT.SourceSlot)), ...
    "CSI feedback ledger must preserve source, due, delivery, and processing causality.");
assert(~isempty(referenceMeasurementT) && all(ismember({'SignalType','ProducerSlot','AvailableSlot','MeasurementSource'}, ...
    referenceMeasurementT.Properties.VariableNames)), ...
    "Reference-signal measurement ledger must preserve producer and availability timing.");
localAssertReceiverSINRDomains(liveChannelStateT, "live channel-state projection");

ok = true;
end

function localAssertBoundControlIdentity(out, cfg)
observed = false;
for field = ["PBCH","PRACH","PDCCH","PUCCH","SRS","TRS"]
    T = sixgr.util.structGet(out, field, table());
    if ~(istable(T) && ~isempty(T))
        continue;
    end
    observed = true;
    required = ["ScenarioID","ConfigHash","RunTag","ExecutionID"];
    assert(all(ismember(required, string(T.Properties.VariableNames))), ...
        "Coupled %s rows must expose the immutable runtime identity.", field);
    assert(all(string(T.ScenarioID) == string(cfg.run.scenarioID)) && ...
        all(lower(string(T.ConfigHash)) == lower(string(cfg.meta.configHash))) && ...
        all(string(T.RunTag) == string(cfg.run.runTag)) && ...
        all(string(T.ExecutionID) == string(cfg.run.executionID)), ...
        "Coupled %s rows must bind the active scenario/config/execution identity.", field);
end
assert(observed, "The focused coupled runtime must emit at least one identity-bound control row.");
end

