    "pucch_resources.overlap_policy.detect_pucch_pusch_overlap", true);
cfg = sixgr.util.structSet(cfg, ...
    "pucch_resources.overlap_policy.uci_on_pusch_enabled", true);
cfg = sixgr.util.structSet(cfg, ...
    "pucch_resources.overlap_policy.unsupported_overlap_policy", ...
    "reject_before_waveform");
cfg = sixgr.util.structSet(cfg, "tdd_timing.dl_harq_feedback_k1", 4);
cfg = sixgr.util.structSet(cfg, "phy.pucch.uciOnPUSCHEnabled", true);
cfg = sixgr.util.structSet(cfg, "phy.pusch.uciMultiplexingMode", ...
    "harq_ack_on_pusch_when_pucch_collides");
slotDuration_s = max(eps, double(sixgr.util.structGet(cfg, "phy.numerology.slotDuration_ms", 1)) / 1e3);

runFolder = fullfile(tmp, "bundle", "air_interface");
opt = struct( ...
    "LinkDuration_s", slotBudget * slotDuration_s, ...
    "LinkMaxSimFrames", slotBudget, ...
    "LinkSNR_dB", cfg.channel.snr_dB, ...
    "LinkSNRGrid_dB", cfg.channel.snr_dB, ...
    "LinkSweepFrames", slotBudget, ...
    "LinkSweepTrialsPerSNR", slotBudget, ...
    "LinkReferenceSweepFrames", slotBudget, ...
    "LinkSweepMaxPoints", 1, ...
    "SaveFigures", false);
