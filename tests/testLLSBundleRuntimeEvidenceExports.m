    all(double(observed.ue_id(data)) >= 1) && ...
    all(isfinite(double(observed.cell_id(data)))) && ...
    all(strlength(strtrim(string(observed.allocation_id(data)))) > 0), ...
    ["Observed PDSCH/PUSCH RE rows must bind the executed UE, serving " + ...
     "base station, frozen grant context, and unique allocation at the producer."]);
