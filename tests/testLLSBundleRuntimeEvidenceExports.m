function localAssertReceiverSINRDomains(T, label)
required = {'MeasuredTrialSINR_dB','SINRMeasurementDomain','PowerReferencePlane'};
missing = required(~ismember(required, T.Properties.VariableNames));
assert(isempty(missing), "%s is missing receiver SINR-domain columns: %s", ...
    label, strjoin(string(missing), ", "));
finiteMask = isfinite(double(T.MeasuredTrialSINR_dB));
assert(any(finiteMask), "%s must contain receiver-measured SINR rows.", label);
domain = strtrim(string(T.SINRMeasurementDomain));
plane = strtrim(string(T.PowerReferencePlane));
validDomain = strlength(domain) > 0 & ~ismissing(domain) & ...
    ~ismember(lower(domain), ["nan","missing","unavailable"]);
validPlane = strlength(plane) > 0 & ~ismissing(plane) & ...
    ~ismember(lower(plane), ["nan","missing","unavailable"]);
bad = finiteMask & ~(validDomain & validPlane);
if any(bad)
    i = find(bad, 1, "first");
    measuredSource = localDiagnosticColumn(T, "MeasuredTrialSINRSource", i);
    postEqSource = localDiagnosticColumn(T, "PostEqSINRSource", i);
    hestSource = localDiagnosticColumn(T, "ReceiverHestSINRSource", i);
    error("sixgr:test:MissingReceiverSINRDomain", ...
        ["%s must identify the measurement domain and reference plane for every finite receiver SINR. " ...
         "First bad row=%d measured=%g measured_source=%s posteq=%s hest=%s domain=%s plane=%s"], ...
        char(string(label)), i, double(T.MeasuredTrialSINR_dB(i)), ...
        char(measuredSource), char(postEqSource), char(hestSource), ...
        char(domain(i)), char(plane(i)));
end
end

function value = localDiagnosticColumn(T, name, row)
if ismember(string(name), string(T.Properties.VariableNames))
    column = T.(char(name));
    value = string(column(row));
else
    value = "<absent>";
end
if ismissing(value)
    value = "<missing>";
end
end

function tf = localAllBlankOrMissing(values)
if isnumeric(values)
    tf = all(~isfinite(double(values)));
    return;
end
vals = string(values);
vals = strip(vals);
tf = all(strlength(vals) == 0 | strcmpi(vals, "nan") | strcmpi(vals, "missing"));
end
