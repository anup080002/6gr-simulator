function localAssertPUSCHHARQACKCausality(out, ulT)
required = ["UCIOnPUSCHApplied","ExpectedHARQACKBits", ...
    "DecodedHARQACKBits","UCIOnPUSCHFeedbackGrantIds", ...
    "UCIOnPUSCHFeedbackSourceSlots","UCIOnPUSCHFeedbackHARQIds", ...
    "UCIOnPUSCHFeedbackBitCount","UCIOnPUSCHEvidenceSource", ...
    "HARQACKContentMatch","HARQACKDecodeStatus"];
assert(all(ismember(required, string(ulT.Properties.VariableNames))), ...
    "UL raw trials must expose exact source-to-decoded PUSCH UCI bindings.");
mux = logical(ulT.UCIOnPUSCHApplied);
assert(any(mux), ...
    "The ten-slot causal coupled fixture must carry due DL HARQ-ACK on its same-UE PUSCH.");
assert(all(double(ulT.UCIOnPUSCHFeedbackBitCount(mux)) > 0) && ...
    all(strlength(strtrim(string(ulT.UCIOnPUSCHFeedbackGrantIds(mux)))) > 0) && ...
    all(strlength(strtrim(string(ulT.UCIOnPUSCHFeedbackSourceSlots(mux)))) > 0) && ...
    all(strlength(strtrim(string(ulT.UCIOnPUSCHFeedbackHARQIds(mux)))) > 0) && ...
    all(strlength(strtrim(string(ulT.ExpectedHARQACKBits(mux)))) > 0) && ...
    all(strlength(strtrim(string(ulT.DecodedHARQACKBits(mux)))) > 0) && ...
    all(contains(lower(strtrim(string(ulT.UCIOnPUSCHEvidenceSource(mux)))), ...
        "same_waveform_pusch_rx")) && ...
    all(lower(string(ulT.HARQACKDecodeStatus(mux))) == "decoded_match"), ...
    "PUSCH UCI rows must retain source grants, HARQ processes, expected bits, receiver-decoded bits, and the actual receiver-demultiplexer evidence source.");

runtime = sixgr.util.structGet(sixgr.util.structGet(out, ...
    "RawTrials", struct()), "CoupledRuntime", struct());
traceT = sixgr.util.structGet(runtime, "PUCCHGrantTraceTable", table());
assert(istable(traceT) && ~isempty(traceT) && ...
    all(ismember(["MultiplexedOnPUSCH","PUSCHUCIDecodeOk", ...
    "GrantExecutedFlag","PUCCHDecodeOk","RuntimeStateUpdated", ...
    "RuntimeStateConsumer"], string(traceT.Properties.VariableNames))), ...
    "Coupled runtime must persist transferred control-grant state.");
transferred = logical(traceT.MultiplexedOnPUSCH);
assert(any(transferred) && ~any(logical(traceT.GrantExecutedFlag(transferred))) && ...
    ~any(logical(traceT.PUCCHDecodeOk(transferred))) && ...
    all(logical(traceT.RuntimeStateUpdated(transferred))) && ...
    all(string(traceT.RuntimeStateConsumer(transferred)) == ...
    "HARQEntity.onFeedback_from_PUSCH_UCI"), ...
    "Transferred HARQ-ACK must update DL HARQ from the same PUSCH " + ...
    "receiver without fabricating a standalone PUCCH waveform execution.");
end

function localAssertFrozenGrantTraceAuthority(out)
rawTrials = sixgr.util.structGet(out, "RawTrials", struct());
runtime = sixgr.util.structGet(rawTrials, "CoupledRuntime", struct());
for direction = ["DL","UL"]
    traceName = char(direction + "GrantTraceTable");
    trialName = char(direction);
    grantT = sixgr.util.structGet(runtime, traceName, table());
    trialT = sixgr.util.structGet(rawTrials, trialName, table());
    assert(istable(grantT) && ~isempty(grantT) && istable(trialT) && ~isempty(trialT), ...
        "Focused %s waveform execution must retain nonempty trial and grant traces.", direction);
    required = ["RequestedPrecoderSHA256","AppliedPrecoderSHA256", ...
        "AppliedPrecoderMatrixSHA256","PrecoderDigestDomain","FrozenGrantContextId"];
    assert(all(ismember(required, string(grantT.Properties.VariableNames))), ...
        "Focused %s grant trace is missing frozen precoder authority columns.", direction);
    requested = lower(strtrim(string(grantT.RequestedPrecoderSHA256)));
    applied = lower(strtrim(string(grantT.AppliedPrecoderSHA256)));
    legacyApplied = lower(strtrim(string(grantT.AppliedPrecoderMatrixSHA256)));
    domain = strtrim(string(grantT.PrecoderDigestDomain));
    context = strtrim(string(grantT.FrozenGrantContextId));
    valid = ~cellfun(@isempty, regexp(cellstr(applied), '^[0-9a-f]{64}$', 'once'));
    assert(any(valid) && all(requested(valid) == applied(valid)) && ...
        all(legacyApplied(valid) == applied(valid)) && ...
        all(strlength(domain(valid)) > 0) && ...
        all(strlength(context(valid)) > 0), ...
        "Focused %s grant trace must prove frozen requested/applied matrix identity.", direction);
end
end

function localAssertBoundControlIdentity(out, cfg)
rawTrials = sixgr.util.structGet(out, "RawTrials", out);
observed = false;
for field = ["PBCH","PRACH","PDCCH","PUCCH","SRS","TRS"]
    T = sixgr.util.structGet(rawTrials, field, table());
    if ~(istable(T) && ~isempty(T))
        continue;
    end
    observed = true;
    required = ["ScenarioID","ConfigHash","RunTag","ExecutionID", ...
        "UEIndex","UEID","RNTI","BaseStationID"];
    assert(all(ismember(required, string(T.Properties.VariableNames))), ...
        "Coupled %s rows must expose the immutable runtime identity.", field);
    assert(all(string(T.ScenarioID) == string(cfg.run.scenarioID)) && ...
        all(lower(string(T.ConfigHash)) == lower(string(cfg.meta.configHash))) && ...
        all(string(T.RunTag) == string(cfg.run.runTag)) && ...
        all(string(T.ExecutionID) == string(cfg.run.executionID)), ...
        "Coupled %s rows must bind the active scenario/config/execution identity.", field);
    assert(all(isfinite(double(T.UEIndex))) && ...
        all(isfinite(double(T.UEID))) && ...
        all(isfinite(double(T.RNTI))) && ...
        all(isfinite(double(T.BaseStationID))) && ...
        all(double(T.UEID) == double(T.UEIndex)), ...
        "Coupled %s rows must bind the executed UE, RNTI, and serving base station at the source.", field);
end
assert(observed, "The focused coupled runtime must emit at least one identity-bound control row.");
end

function localAssertULSchedulerDecisionLineage(out)
rawTrials = sixgr.util.structGet(out, "RawTrials", out);
runtime = sixgr.util.structGet(rawTrials, "CoupledRuntime", struct());
grantT = sixgr.util.structGet(runtime, "ULGrantTraceTable", table());
decisionT = sixgr.util.structGet(runtime, "SchedulerDecisionTable", table());
assert(istable(grantT) && ~isempty(grantT), ...
    "The focused ten-slot SRS-to-K2 fixture must execute at least one UL grant.");
assert(istable(decisionT) && ~isempty(decisionT), ...
    "UL grants require persisted scheduler candidate-decision lineage.");
required = ["Direction","ControlSlot","ScheduledDataSlot","K2Slots", ...
    "Scheduled","RNTI","UEIndex","SchedulingTimingMode"];
assert(all(ismember(required, string(decisionT.Properties.VariableNames))), ...
    "K2 scheduler decisions are missing control/data-slot lineage columns.");
ul = upper(strtrim(string(decisionT.Direction))) == "UL";
assert(any(ul) && all(isfinite(double(decisionT.ControlSlot(ul)))) && ...
    all(isfinite(double(decisionT.ScheduledDataSlot(ul)))) && ...
    all(double(decisionT.ScheduledDataSlot(ul)) - ...
        double(decisionT.ControlSlot(ul)) == double(decisionT.K2Slots(ul))) && ...
    all(string(decisionT.SchedulingTimingMode(ul)) == "dci_k2_future_ul"), ...
    "Every UL K2 decision must retain exact control-slot, data-slot, and K2 causality.");
scheduledRNTI = double(decisionT.RNTI(ul & logical(decisionT.Scheduled)));
grantRNTI = double(grantT.RNTI);
assert(~isempty(scheduledRNTI) && all(ismember(grantRNTI, scheduledRNTI)), ...
    "Every executed UL grant must be traceable to a scheduled UL candidate decision.");
end

