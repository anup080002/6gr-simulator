cfg.meta.scenarioID = char(string(scfg.ScenarioID));
cfg.meta.executionID = cfg.run.executionID;
cfg.meta.configHash = char(string(scfg.ConfigHash));
% Ten canonical slots are the minimal causal codebook-PUSCH slice.  The
% first D,D,D,U,U period produces the measured SRS in slot 4; only the
% following DL control occasion may consume that SRS to select SRI/TPMI/RI
% and schedule K2=4 PUSCH in slot 10.  A five-slot fixture would bypass the
% required SRS producer or incorrectly expect an unmeasured UL grant.
slotBudget = 10;
cfg.run.numFrames = slotBudget;
cfg.scenario.nUE = 1;
cfg.scenario.ue.nUE = 1;
cfg = sixgr.util.structSet(cfg, "lls6g.users.n_users", 1);
cfg = sixgr.util.structSet(cfg, "lls6g.users.enabled", true);
cfg = sixgr.util.structSet(cfg, "lls6g.users.execution_model", "slot_coupled_truth");
