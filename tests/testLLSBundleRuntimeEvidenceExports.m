    string(sixgr.util.structGet(typedCSI, "ReportConfigID", "")) == ...
    "csi-report-runtime-0", ...
    ["The waveform scenario YAML must resolve its typed CSI UCI schema " + ...
     "before any coupled runtime state is created."]);
