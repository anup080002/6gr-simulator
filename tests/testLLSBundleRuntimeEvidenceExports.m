function localAssertAllCSIRS(T, condition, fieldName, values)
bad = find(~reshape(logical(condition), [], 1));
if isempty(bad)
    return;
end
slots = string(T.Slot(bad));
observed = reshape(string(values), [], 1);
observed = observed(bad);
observed(ismissing(observed)) = "<missing>";
detail = strjoin("slot=" + slots + ":" + fieldName + "=" + observed, "; ");
assert(false, sprintf("Runtime CSI-RS evidence failed field %s at %s.", ...
    char(fieldName), char(detail)));
end

