function ok = testRANegativeSetupCompleteCRC()
% A physical UL decode failure must terminate access, not throw on a NaN ID.
cfg = raStrictAnchorConfig();
res = sixgr.phy.ra.runFourStepRA(cfg, ...
    "FaultMode","rrc_setup_complete_crc_failure","WriteArtifacts",false);
assert(res.Msg4PDCCHCrcPass && res.Msg4PDSCHCrcPass && res.RRCSetupDecoded, ...
    'The negative case must reach accepted Msg4 before corrupting SetupComplete.');
assert(~res.RACompleted && ~res.RRCSetupCompleteCRC && ~res.RRCSetupCompleteDecoded && ...
    ~res.RRCConnected && ~res.StrictOk, ...
    'A failed physical SetupComplete must not produce connected access.');
assert(res.FailureReason=="rrc_setup_complete_decode_or_state_failure", ...
    'Missing decoded identity must remain a receiver failure, not an input-parser exception.');
assert(isnan(res.RRCSetupCompleteDecodedTransactionID) && ...
    strlength(res.RRCSetupCompleteDecodedUEIdentity)==0, ...
    'No transmitted transaction or identity may rescue a CRC-failed UL message.');
assert(res.SRB1Installed && res.RRCState.SetupCompleteIdentityEvidenceProvided && ...
    res.RRCState.ErrorIdentifier=="sixgr:phy:ia:RRCSetupCompleteFailure" && ...
    res.RRCState.FailureEventOrdinal==4, ...
    'Accepted Msg4 configuration survives; the distinct UL completion fails.');
assert(res.RRCState.Trace.GNBStateAfter(3)=="WAIT_SETUP_COMPLETE", ...
    'Do not misclassify a failed UL message as a failed Msg4.');
ok = true;
end
