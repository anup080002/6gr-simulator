function ok = testE2ETruthChunkMetadata()
%TESTE2ETRUTHCHUNKMETADATA Truth E2E metadata must expose chunking and coupling.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

cfg = sixgr.config.defaultConfig();
cfg.run.strictMode = true;
cfg.channel.model = "TDL-C";
cfg.channel.awgnOnly = false;
cfg.channel.dopplerHz = 70;
cfg.channel.fading.enable = true;
cfg.channel.fading.model = "TDL";
cfg.channel.fading.profile = "TDL-C";
cfg.channel.fading.maxDoppler_Hz = 70;
cfg.traffic.model = "fullBuffer";
cfg.traffic.transport = "UDP";
cfg.traffic.flowDirection = "UL";
cfg.traffic.packetSize_bytes = 256;
cfg.traffic.flows = struct([]);
cfg.scenario.ue.nUE = 1;
cfg.scenario.nUE = 1;

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmp, ...
    "OnlyE2E", true, ...
    "RunLinkCampaign", false, ...
    "RunDetailedLinkDiagnostics", false, ...
    "RunSystemMMTCProbe", false, ...
    "RunAuxiliaryProbes", false, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", 0.01, ...
    "E2EMaxSlots", 20, ...
    "E2EUECount", 1, ...
    "E2ETrafficModel", "fullbuffer", ...
    "E2EAirModel", "truth", ...
    "E2EStrictValidation", true, ...
    "E2ETruthFastAWGNPath", false, ...
    "E2ETruthCompactPHYIO", true, ...
    "E2ETruthAdaptiveLDPC", true, ...
    "E2ETruthLDPCMaxIterations", 0, ...
    "E2ETruthUseGPU", false, ...
    "E2ETruthMaxSlots", 20, ...
    "LinkSNR_dB", 30, ...
    "CalibrateSystemBLERFromLink", false, ...
    "UseFastLinkModel", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "GenerateCampaignPlots", false, ...
    "VerifyArtifacts", false, ...
    "Verbose", false);

layout = sixgr.report.resultLayout(char(string(rep.RunFolder)));
summaryCsv = fullfile(layout.PacketFlowCSVDir, "probe_e2e_summary_truth.csv");
T = readtable(summaryCsv, "VariableNamingRule", "preserve");
assert(height(T) >= 1, "Truth E2E summary should contain one row.");
assert(ismember("AppSDUChunkBytes", string(T.Properties.VariableNames)), ...
    "Truth E2E summary must expose AppSDUChunkBytes.");
assert(ismember("AppSDUChunkSource", string(T.Properties.VariableNames)), ...
    "Truth E2E summary must expose AppSDUChunkSource.");
assert(ismember("E2ESystemCoupled", string(T.Properties.VariableNames)), ...
    "Truth E2E summary must expose E2ESystemCoupled.");
assert(ismember("E2ECouplingMode", string(T.Properties.VariableNames)), ...
    "Truth E2E summary must expose E2ECouplingMode.");
assert(ismember("E2EAirModelSource", string(T.Properties.VariableNames)), ...
    "Truth E2E summary must expose E2EAirModelSource.");
assert(ismember("AirInterfaceBackend", string(T.Properties.VariableNames)), ...
    "Truth E2E summary must expose AirInterfaceBackend.");
assert(double(T.AppSDUChunkBytes(1)) == 256, ...
    "Truth E2E chunking should derive from the configured packet size when no explicit RLC chunk is set.");
assert(string(T.AppSDUChunkSource(1)) == "traffic_flow_packet_size_bytes", ...
    "Truth E2E chunk source should identify packet-size-derived chunking.");
assert(string(T.E2EAirModelSource(1)) == "system_waveform_grant_trace", ...
    "Truth E2E summary must report the system-coupled waveform grant trace source.");
assert(string(T.AirInterfaceBackend(1)) == "WAVEFORM_SYSTEM_PHY", ...
    "Truth E2E summary must report the waveform system PHY backend.");
assert(logical(T.E2ESystemCoupled(1)), ...
    "Truth E2E summary must state that truth replay is now system-coupled.");
assert(string(T.E2ECouplingMode(1)) == "system_waveform_grant_trace", ...
    "Truth E2E summary must report the system waveform grant trace coupling mode.");

manifest = jsondecode(fileread(layout.RunManifestJSON));
assert(isfield(manifest, "E2ESystemCoupled") && logical(manifest.E2ESystemCoupled), ...
    "Run manifest must record system-coupled truth E2E.");
assert(isfield(manifest, "E2ECouplingMode") && string(manifest.E2ECouplingMode) == "system_waveform_grant_trace", ...
    "Run manifest must record the waveform system grant trace coupling mode.");
assert(isfield(manifest, "E2EAppSDUChunkBytes") && double(manifest.E2EAppSDUChunkBytes) == 256, ...
    "Run manifest must record packet-sized E2E chunking.");

reportText = fileread(layout.CampaignReportMD);
assert(contains(reportText, "- System-coupled execution: `true`"), ...
    "Markdown report must state that truth E2E is system-coupled.");
assert(contains(reportText, "- E2E coupling mode: `system_waveform_grant_trace`"), ...
    "Markdown report must state the waveform system grant trace coupling mode.");

ok = true;
end
