function [ok,checks,evidenceFolder]=testPUSCHPhysicalPartialHARQCompletion()
% One native encoded PUSCH waveform, two independently configured RX calls.
% Declared unit-AWGN PHY component evidence, NOT shared-owner completion,
% received DCI, MAC delivery, natural HARQ gain or statistical qualification.
% In particular the reducer identities below are declared test identities;
% they do not replace the real scheduler/capture joins required by the owner.
setup6GRSimToolkit('Verbose',false,'RunToolboxChecks',false);
originalRNG=rng; cleanup=onCleanup(@()rng(originalRNG)); %#ok<NASGU>
repository=fileparts(fileparts(mfilename('fullpath')));
parent=fullfile(repository,'results','validation');
if ~isfolder(parent), mkdir(parent); end
evidenceFolder=string(tempname(parent)); mkdir(evidenceFolder);
fprintf('PUSCH_PHYSICAL_PARTIAL_HARQ evidence=%s\n',evidenceFolder);
sources=sourceHashes(repository);
scope=struct('Source',"declared_unit_AWGN_native_PUSCH_component_test", ...
    'WaveformAmplitudeUnit',"normalized",'TransmitterInvocations',0, ...
    'ReceiverInvocations',0,'SharedOwnerCompletionExecuted',false, ...
    'LinkRunnerExecuted',false,'ReceivedControlProved',false, ...
    'PriorSoftBufferPreservationProved',false,'StatisticalQualification',false);
seed=192401; gridNoiseVariance=1e-4; maxIterations=25;
cfg=sixgr.config.defaultConfig(); cfg.run.useMex=false;
cfg.channel.model='AWGN'; cfg.channel.nTxAnt=1; cfg.channel.nRxAnt=1;
cfg.phy.nTxAnt=1; cfg.phy.nRxAnt=1;
cfg.phy.pusch.numLayers=1; cfg.phy.pusch.nLayers=1;
cfg.phy.pusch.mcsTable='qam64_table1'; cfg.phy.pusch.transformPrecoding=false;
cfg.phy.ldpc.maxIterations=maxIterations;
cfg.phy.ofdm.windowingSamples=0;
carrier=nrCarrierConfig('NSizeGrid',12,'SubcarrierSpacing',15, ...
    'NStartGrid',0,'NFrame',0,'NSlot',0);
pusch=nrPUSCHConfig('PRBSet',0:5,'SymbolAllocation',[0 14], ...
    'NumLayers',1,'Modulation','QPSK','TransformPrecoding',false, ...
    'BetaOffsetACK',20,'BetaOffsetCSI1',6.25,'BetaOffsetCSI2',6.25);
pusch.DMRS.DMRSPortSet=0;
rate=.3; tbs=512; initialIMCS=4;
bits=zeros(tbs,1,'int8'); ack=zeros(4,1,'int8');
request=struct('ReportConfigID',"declared_physical_partial_CSI_schema", ...
    'Epoch',0,'CodebookType',"typeI-SinglePanel",'Ports',2, ...
    'Rank',1,'MaxRank',2,'ReportQuantity',"cri-RI-PMI-CQI", ...
    'NumCSIResources',1,'FrequencyGranularity',"wideband",'UCIChannel',"PUSCH");
report=sixgr.phy.mimo.CSIReportConfiguration(request,0);
data=struct('ObservationID',"declared_native_PUSCH_capture", ...
    'ConfigurationEpoch',0,'AssignmentDigest',"declared_component_UL_coding_assignment", ...
    'HARQMappingDigest',"declared_component_four_HARQ_bits", ...
    'HARQACKBitCount',4,'ConfiguredGrantUCIBitCount',0, ...
    'CSIReportConfigID',report.ReportConfigID,'CSIConfigurationEpoch',report.Epoch);
context=sixgr.phy.ul.pusch.PUSCHUCIReceiveContext(data);
% Both schemas are installed before TX. The second is an explicit control,
% not a receiver fallback selected after inspecting the transmitted payload.
noCSIData=data; noCSIData.CSIReportConfigID=""; noCSIData.CSIConfigurationEpoch=NaN;
noCSIContext=sixgr.phy.ul.pusch.PUSCHUCIReceiveContext(noCSIData);
payload=sixgr.phy.ul.pusch.PUSCHUCIPayload('HARQACK',ack);
save(fullfile(evidenceFolder,'original_configuration.mat'),'cfg','carrier','pusch', ...
    'request','report','context','noCSIContext','payload','bits','ack','rate','tbs', ...
    'initialIMCS','seed','gridNoiseVariance','maxIterations','sources','scope','originalRNG');

try
    scope.TransmitterInvocations=scope.TransmitterInvocations+1;
    tx=sixgr.phy.ul.PUSCH_Tx(cfg,'Carrier',carrier,'PUSCH',pusch, ...
        'TargetCodeRate',rate,'NumTxAnt',1,'UCIPayload',payload, ...
        'TransportBlockBits',bits,'TransportBlockSizeOverride',tbs, ...
        'InitialIMCSPerCodeword',initialIMCS,'RV',0,'ExecutionProfile','phy_calibration');
    % Actual native unnormalized FFT: grid variance = Nfft * sample variance.
    % Noise is drawn once, with a private stream, and NEVER replaced by LLRs.
    privateStream=RandStream('mt19937ar','Seed',seed);
    originalNoiseState=privateStream.State;
    sampleNoiseVariance=gridNoiseVariance/double(tx.OFDM.Nfft);
    noise=sqrt(sampleNoiseVariance/2)*complex( ...
        randn(privateStream,size(tx.Waveform)),randn(privateStream,size(tx.Waveform)));
    finalNoiseState=privateStream.State;
    received=tx.Waveform+noise;
    hashes=struct('Transmitted',arrayHash(tx.Waveform),'Noise',arrayHash(noise), ...
        'Received',arrayHash(received));
    rxArgs={'Carrier',carrier,'PUSCH',pusch,'TransportBlockSize',tbs, ...
        'TargetCodeRate',rate,'RV',0,'InitialIMCSPerCodeword',initialIMCS, ...
        'NoiseVar',gridNoiseVariance,'NoiseVarDomain','grid', ...
        'MaxIterations',maxIterations,'SkipTimingEstimate',true, ...
        'FastAWGNPath',false,'ExecutionProfile','phy_calibration'};
    save(fullfile(evidenceFolder,'original_waveform.mat'),'tx','noise','received', ...
        'sampleNoiseVariance','originalNoiseState','finalNoiseState','hashes','rxArgs','scope');
    scope.ReceiverInvocations=scope.ReceiverInvocations+1;
    [partial,partialInfo]=sixgr.phy.ul.PUSCH_Rx(received,cfg,rxArgs{:}, ...
        'UCIReceiveContext',context,'UCIReportConfiguration',report);
    % Preserve the ORIGINAL receiver result before any new outcome assertion.
    save(fullfile(evidenceFolder,'original_partial_receiver.mat'),'partial','partialInfo','hashes','scope');
    scope.ReceiverInvocations=scope.ReceiverInvocations+1;
    [control,controlInfo]=sixgr.phy.ul.PUSCH_Rx(received,cfg,rxArgs{:}, ...
        'UCIReceiveContext',noCSIContext,'UCIReportConfiguration',[]);
    save(fullfile(evidenceFolder,'original_control_receiver.mat'),'control','controlInfo','hashes','scope');
catch cause
    failure=struct('Identifier',string(cause.identifier), ...
        'Report',string(getReport(cause,'extended','hyperlinks','off')));
    save(fullfile(evidenceFolder,'execution_failure.mat'),'failure','scope','sources');
    rethrow(cause);
end

rows=repmat(struct('Case',"",'Passed',false,'ErrorID',"",'Detail',""),0,1);
record("actual_waveform_ambiguous_CSI_partial_ULSCH",@assertPartial);
record("identical_waveform_no_CSI_obligation_control",@assertControl);
record("actual_partial_fields_to_declared_completion_reducer",@assertReducer);
record("original_inputs_sources_and_RNG_unchanged",@assertUnchanged);
checks=struct2table(rows);
save(fullfile(evidenceFolder,'completion.mat'),'checks','scope','sources','hashes');
for k=find(~checks.Passed).'
    fprintf(2,'PUSCH_PHYSICAL_PARTIAL_HARQ %s FAIL %s %s\n', ...
        checks.Case(k),checks.ErrorID(k),checks.Detail(k));
end
assert(all(checks.Passed),'test:PUSCHPhysicalPartialHARQCompletion', ...
    '%d/%d groups failed; original evidence=%s',nnz(~checks.Passed),height(checks),evidenceFolder);
ok=true;
fprintf(['PUSCH_PHYSICAL_PARTIAL_HARQ_PASS TX=1 RX=2 waveform_instances=1 ' ...
    'partial_ULSCH=1 independent_HARQ=1 reducer=1 shared_owner=0 ' ...
    'prior_soft_preservation=0 statistical_qualification=0 evidence=%s\n'],evidenceFolder);

    function record(name,action)
        row=struct('Case',name,'Passed',false,'ErrorID',"",'Detail',"");
        try, action(); row.Passed=true;
        catch cause
            row.ErrorID=string(cause.identifier);
            row.Detail=string(getReport(cause,'extended','hyperlinks','off'));
        end
        rows(end+1,1)=row; %#ok<AGROW>
    end
    function assertPartial()
        e=partial.CSIPresenceEvidence;
        assert(isequal(e.CandidateTBDecodeAttempted,true(2,1)) && ...
            isequal(e.CandidateTBCRCPass,ones(2,1)) && ~e.Resolved && ...
            isnan(e.SelectedCandidate) && ~e.PriorHARQSoftBufferUsed && ...
            ~e.TransmitterMetadataUsed && e.ReceiverContextDigest==context.Digest, ...
            'test:PhysicalAmbiguityNotObserved', ...
            'Both CRC-valid interpretations must arise from the actual received waveform.');
        assert(partial.PartialReception && ~partial.CSIPresenceResolved && ...
            ~partial.ULSCHMappingResolved && ~partial.ULSCHDecodeAttempted && ...
            ~partial.DecodeAttempted && ~partial.TransportBlockCRCAvailable && ...
            isnan(partial.TransportBlockCRCPassPerCodeword) && ...
            isnan(partial.TransportBlockCRCErrorPerCodeword) && ...
            isempty(partial.TransportBlock) && isempty(partial.ULSCHLLR{1}) && ...
            isempty(fieldnames(partial.CodewordDecodeEvidence{1}.CodingLayout)));
        assert(~partial.Ok && ~partial.StrictOk && partial.ReceiverUsable && ...
            partial.ChannelEstimateAvailable && partial.ResourceExtractionAvailable && ...
            partial.EqualizationAvailable && ~partial.UCIReferenceScoringAvailable && ...
            ~isfield(partial,'HARQSoftBuffer') && ~isfield(partial,'SoftBuffer'));
        observed=sixgr.truth.normalizeReceivedPUSCHHARQ(partial,context);
        assert(observed.DecodeAttempted && observed.DecodeOk && ~observed.DTXFlag && ...
            isequal(observed.DecodedBits,ack) && ...
            partial.UCIReceiverEvidence.HARQACK.DecodeUsable);
        assert(~partial.LDPCParityEvidence.Available && ...
            partial.LDPCParityEvidence.Stage=="" && ...
            isequal(partial.LDPCParityEvidence.CodewordStages,""));
        save(fullfile(evidenceFolder,'normalized_original_HARQ.mat'),'observed');
    end
    function assertControl()
        assert(control.DecodeAttempted && control.ULSCHDecodeAttempted && ...
            control.Ok && control.TBCRCPass && ~control.CRCError && ...
            isequal(control.TransportBlock,bits) && ...
            isequal(control.DecodedHARQACKBits,ack) && ~control.UCIReferenceScoringAvailable);
        assert(control.UCIReceiveContextDigest==noCSIContext.Digest && ...
            noCSIContext.Digest~=context.Digest);
        % ChannelEstimate is the common retained owner field. Only the
        % partial branch additionally exposes the Hest local-name alias.
        % No front-end or LLR change is permitted between the two schemas.
        assert(isequaln(partial.Hest,partial.ChannelEstimate) && ...
            isequaln(partial.ChannelEstimate,control.ChannelEstimate) && ...
            isequaln(partial.LayerEqualizedSymbolsForEvidence,control.LayerEqualizedSymbolsForEvidence) && ...
            isequaln(asCells(partial.CodewordLLR),asCells(control.CodewordLLR)));
        observed=sixgr.truth.normalizeReceivedPUSCHHARQ(control,noCSIContext);
        assert(observed.DecodeOk && isequal(observed.DecodedBits,ack));
        assert(double(tx.CodingLayout.NumCodeBlocks)==1 && tx.OFDMWindowingSamples==0 && ...
            size(received,2)==1 && size(received,1)<=8192 && ...
            isempty(tx.CSIPart1Bits) && isempty(tx.CSIPart2Bits));
    end
    function assertReducer()
        % Actual receiver flags enter the production reducer unchanged. Only
        % its scheduling token is declared: no full shared-completion claim.
        attempt=struct('ScopeKey',"declared_component_UL_process", ...
            'ReceiverKey',"gNB-UL-TB-declared-physical-partial-component",'NDIEpoch',0, ...
            'DataAbsoluteSlot',0,'ObservationID',context.Data.ObservationID, ...
            'GrantContextID',"declared_component_grant_not_received_DCI", ...
            'CommandObservationID',"declared_component_command_not_air_control", ...
            'StartSample',0,'EndSampleExclusive',size(received,1), ...
            'SampleRateHz',double(tx.OFDM.SampleRate),'AvailableAtSample',size(received,1));
        % The namespace is a reducer input contract, not scheduling proof.
        % Keep the original malformed fixture identity as a strict negative.
        badAttempt=attempt; badAttempt.ReceiverKey="declared_component_gNB_UL_TB";
        reject(@()sixgr.truth.resolveULHARQReceiverState({},badAttempt), ...
            'sixgr:link:ULHARQReceiverKeyRequired');
        [records,prior,token]=sixgr.truth.resolveULHARQReceiverState({},attempt);
        assert(isempty(records) && isempty(prior));
        flags=struct();
        for name=["NoiseVarStrictFailure","DecodeAttempted","ULSCHDecodeAttempted","ReceiverUsable"]
            flags.(name)=partial.(name);
        end
        originalObservation=sixgr.truth.normalizeReceivedPUSCHHARQ(partial,context);
        out=struct('IndependentUCICompletionFlags',flags,'ReceiverHARQAttempt',token, ...
            'CombinedDecodeOK',partial.Ok,'DecodedHARQACKBits',partial.DecodedHARQACKBits, ...
            'UCIReceiverEvidence',partial.UCIReceiverEvidence, ...
            'IndependentHARQObservation',originalObservation);
        before=out;
        decision=sixgr.truth.preparePUSCHULHARQReceiverDecision(out);
        after=sixgr.truth.resolveULHARQReceiverState(records,attempt,decision);
        assert(~decision.DecodeAttempted && ~decision.CRCPass && isempty(decision.SoftBuffer) && ...
            isempty(after{1}.SoftBuffer) && ~after{1}.DecodeAttempted && ~after{1}.CRCPass && ...
            isequaln(before,out) && isequaln(after{1}.Attempt,attempt));
        % Internal reducer false is not a new public CRC failure. Original
        % no-CRC data and independently usable received UCI remain separate.
        assert(isnan(partial.TransportBlockCRCPassPerCodeword) && originalObservation.DecodeOk);
        reject(@()sixgr.truth.resolveULHARQReceiverState(after,attempt,decision), ...
            'sixgr:truth:StaleULHARQReceiveAttempt');
        bad=out; bad.CombinedDecodeOK=true;
        reject(@()sixgr.truth.preparePUSCHULHARQReceiverDecision(bad), ...
            'sixgr:truth:InvalidULHARQReceiverDecision');
        bad=out; bad.IndependentUCICompletionFlags.ULSCHDecodeAttempted=true;
        reject(@()sixgr.truth.preparePUSCHULHARQReceiverDecision(bad), ...
            'sixgr:truth:ULHARQReceiverSoftEvidenceRequired');
        bad=out; bad.SoftBuffer=control.HARQSoftBuffer;
        reject(@()sixgr.truth.preparePUSCHULHARQReceiverDecision(bad), ...
            'sixgr:truth:UnattemptedULHARQSoftEvidence');
        reject(@()sixgr.truth.normalizeReceivedPUSCHHARQ(partial,noCSIContext), ...
            'sixgr:truth:PUSCHHARQReceiveContextMismatch');
        save(fullfile(evidenceFolder,'declared_reducer_result.mat'), ...
            'attempt','out','decision','after','originalObservation');
    end
    function assertUnchanged()
        assert(scope.TransmitterInvocations==1 && scope.ReceiverInvocations==2 && ...
            hashes.Transmitted==arrayHash(tx.Waveform) && hashes.Noise==arrayHash(noise) && ...
            hashes.Received==arrayHash(received) && isequaln(received,tx.Waveform+noise));
        assert(isequaln(rng,originalRNG),'The private-noise fixture changed global RNG.');
        assert(isequal(sources,sourceHashes(repository)),'Source files changed during this test.');
    end
end

function cells=asCells(value)
if iscell(value), cells=reshape(value,1,[]); else, cells={value}; end
end

function value=arrayHash(value)
value=string(sixgr.phy.waveform.WaveformHash.numeric(value));
end

function sources=sourceHashes(repository)
paths=["tests/testPUSCHPhysicalPartialHARQCompletion.m", ...
    "+sixgr/+phy/+ul/PUSCH_Tx.m","+sixgr/+phy/+ul/PUSCH_Rx.m", ...
    "+sixgr/+phy/+ul/+pusch/receiveConfiguredUCI.m", ...
    "+sixgr/+phy/+ul/+pusch/receiveWithCSIPresence.m", ...
    "+sixgr/+phy/+ul/+pusch/receiveInvariantUCI.m", ...
    "+sixgr/+phy/+ul/+pusch/decodeResolvedULSCH.m", ...
    "+sixgr/+phy/+ul/+pusch/PUSCHUCIMultiplexer.m", ...
    "+sixgr/+phy/+ul/+pusch/PUSCHUCIDemultiplexer.m", ...
    "+sixgr/+truth/normalizeReceivedPUSCHHARQ.m", ...
    "+sixgr/+truth/preparePUSCHULHARQReceiverDecision.m", ...
    "+sixgr/+truth/resolveULHARQReceiverState.m"];
digest=strings(numel(paths),1);
for k=1:numel(paths), digest(k)=string(sixgr.util.sha256File(fullfile(repository,paths(k)))); end
sources=table(paths(:),digest,'VariableNames',{'SourceFile','SHA256'});
end

function reject(action,identifier)
try, action(); catch cause
    assert(strcmp(cause.identifier,identifier),'Expected %s, got %s: %s', ...
        identifier,cause.identifier,cause.message); return;
end
error('test:MissingRejection','Expected %s.',identifier);
end
