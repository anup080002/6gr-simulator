function testSynchronizationStateSignConventions()
%TESTSYNCHRONIZATIONSTATESIGNCONVENTIONS Receiver timing/CFO sign contract.

sync = sixgr.phy.sync.resolveSynchronizationState( ...
    "SampleRate_Hz", 30.72e6, ...
    "InjectedCFO_Hz", 100, ...
    "EstimatedCFO_Hz", 90, ...
    "AppliedCFOCorrection_Hz", 90, ...
    "InjectedTimingOffset_samples", 7, ...
    "RawTimingEstimate_samples", 9, ...
    "KnownTimingDelay_samples", 2, ...
    "AppliedTimingCorrection_samples", 7, ...
    "TimingEstimateUsed", true, ...
    "PhysicalDoppler_Hz", 25, ...
    "EstimatedCommonFrequency_Hz", 115);

assert(abs(sync.ResidualCFO_PostCorrection_Hz - 10) < 1e-12, ...
    "CFO residual must equal injected oscillator CFO minus applied correction.");
assert(abs(sync.EstimatedTimingOffsetForCorrection_samples - 7) < 1e-12, ...
    "Timing correction input must subtract known implementation delay.");
assert(abs(sync.ResidualTimingError_PostCorrection_samples) < 1e-12, ...
    "Timing residual must equal injected timing minus applied correction.");
assert(contains(string(sync.CFOCorrectionConvention), "exp_minus_j2pi"), ...
    "CFO correction sign convention must be explicit.");

fs = 30.72e6;
dt = 2e-3;
commonHz = 125;
oscillatorHz = 100;
physicalDopplerHz = 25;
det = struct();
det.SlotDetections = repmat(struct( ...
    "Slot", NaN, ...
    "Detected", true, ...
    "RxRE", complex(1), ...
    "ReferenceSymbols", complex(1)), 2, 1);
det.SlotDetections(1).Slot = 0;
det.SlotDetections(2).Slot = 2;
det.SlotDetections(1).RxRE = complex(1);
det.SlotDetections(2).RxRE = exp(1j * 2 * pi * commonHz * dt);
tx = struct();
tx.SampleRateHz = fs;
tx.SlotTable = table([1; 1 + round(dt * fs)], 'VariableNames', {'StartSample1Based'});
cfg = struct("RunId", "sync_sign_test", "ConfigHash", "sync_sign_hash", "FrequencyToleranceHz", 1e-6);
rx = struct("InjectedCFO_Hz", oscillatorHz, "PhysicalDoppler_Hz", physicalDopplerHz);

freq = sixgr.phy.trs.estimateTRSFrequencyOffset(det, cfg, tx, rx);
assert(freq.EstimateAvailable, "TRS frequency estimate should be available for two detected slots.");
assert(abs(freq.EstimatedCommonFrequency_Hz - commonHz) < 1e-9, ...
    "TRS common phase estimate should preserve total observed phase rate.");
assert(abs(freq.EstimatedCFO_Hz - oscillatorHz) < 1e-9, ...
    "TRS oscillator CFO must subtract physical Doppler from common phase rate.");
assert(abs(freq.FrequencyError_Hz) < 1e-9, ...
    "Frequency error must be oscillator CFO estimate minus injected oscillator CFO.");
end
