function testSynchronizationStateSignConventions()
%TESTSYNCHRONIZATIONSTATESIGNCONVENTIONS Receiver timing/CFO sign contract.
setup6GRSimToolkit('Verbose',false);

sync = sixgr.phy.sync.resolveSynchronizationState( ...
    "SampleRate_Hz", 30.72e6, ...
    "InjectedCFO_Hz", 100, ...
    "EstimatedCFO_Hz", 90, ...
    "AppliedCFOCorrection_Hz", 90, ...
    "InjectedTimingOffset_samples", 7, ...
    "RawTimingEstimate_samples", 9, ...
    "KnownTimingDelay_samples", 2, ...
    "AppliedTimingCorrection_samples", 7, ...
    "TimingEstimateUsed", true, ...
    "PhysicalDoppler_Hz", 25, ...
    "EstimatedCommonFrequency_Hz", 115);

assert(abs(sync.ResidualCFO_PostCorrection_Hz - 10) < 1e-12, ...
    "CFO residual must equal injected oscillator CFO minus applied correction.");
assert(abs(sync.EstimatedTimingOffsetForCorrection_samples - 7) < 1e-12, ...
    "Timing correction input must subtract known implementation delay.");
assert(abs(sync.ResidualTimingError_PostCorrection_samples) < 1e-12, ...
    "Timing residual must equal injected timing minus applied correction.");
assert(contains(string(sync.CFOCorrectionConvention), "exp_minus_j2pi"), ...
    "CFO correction sign convention must be explicit.");

commonHz = 125;
s=sixgr.lls6g.config.loadScenarioConfig(fullfile('simulator','configs', ...
    'scenarios','lls_causal_access_to_data_wiring_tdd.yaml'));
cfg=sixgr.lls6g.buildInternalConfig(s,tempname);
runtimeSlot=double(cfg.phy.trs.slotNumbers(1))+1;
p=sixgr.link.prepareTRSTransmission(cfg,12,'RuntimeSlot',runtimeSlot);
tx=p.Tx;
t=(0:size(tx.Waveform,1)-1)'/tx.SampleRateHz;
rx=struct('Waveform',tx.Waveform.*exp(1i*2*pi*commonHz*t), ...
    'NoiseVariance',0,'InjectedCFO_Hz',100,'PhysicalDoppler_Hz',25, ...
    'InjectedTimingOffset_samples',0);
timing=sixgr.phy.trs.estimateTRSTiming(rx,p.StrictConfig,tx);
det=sixgr.phy.trs.detectTRSResources(rx,p.StrictConfig,tx,'Timing',timing);
evaluation=struct('FrequencyReferenceForScoring_Hz',commonHz, ...
    'FrequencyReferenceForScoringSource','unit_fixture_received_common_frequency');
freq=sixgr.phy.trs.estimateTRSFrequencyOffset(det,p.StrictConfig,tx,evaluation);
assert(freq.EstimateAvailable, ...
    "TRS frequency estimate should be available from its two within-slot symbols.");
assert(abs(freq.EstimatedCommonFrequency_Hz - commonHz) < 0.1, ...
    "TRS common phase estimate should preserve total observed phase rate.");
assert(freq.EstimatedCFO_Hz==freq.EstimatedCommonFrequency_Hz && ...
    isnan(freq.EstimatedOscillatorCFO_Hz) && isnan(freq.PhysicalDoppler_Hz), ...
    "TRS alone must not invent a separation between oscillator CFO and Doppler.");
assert(abs(freq.FrequencyError_Hz) < 0.1, ...
    "Frequency scoring must compare against the declared common-frequency reference.");
assert(string(freq.FrequencyEstimateDomain)=="received_TRS_common_phase_frequency");
end
