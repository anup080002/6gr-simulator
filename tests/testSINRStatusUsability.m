function ok = testSINRStatusUsability()
%TESTSINRSTATUSUSABILITY Guard shared measured-SINR status vocabulary.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

localAssertUtilityContract();
localAssertMeasuredSINRCurveFilterUsesSharedContract();
localAssertControlReferenceStrictUsesSharedContract();

ok = true;
end

function localAssertUtilityContract()
statuses = ["OK"; "OK_dynamic_range_limited"; "OK_decision_residual_bounded"; ...
    "OK_future_estimator_variant"; "ok_lowercase_variant"; "unavailable"; ...
    "NOT_AVAILABLE"; "available_system_level_estimate"; "rejected"; ...
    "quarantined"; ""; missing];
expected = [true; true; true; true; true; false; false; false; false; false; false; false];
actual = sixgr.util.isAcceptableSINRStatus(statuses);
assert(isequal(actual(:), expected(:)), ...
    "Shared SINR status utility must accept every OK* measured variant and reject non-OK statuses.");
unsafe=["OK_PROXY","OK_fast_proxy_estimator","OK_FALLBACK","OK_SYNTHETIC", ...
    "OK_LUT","OK_LOGISTIC","OK_QUARANTINED","OK_REJECTED","OK_UNAVAILABLE", ...
    "OK_NOT_AVAILABLE","OK_LOWER_BOUND_NOISE_FLOOR","OKAY","OK-proxy"];
assert(~any(sixgr.util.isAcceptableSINRStatus(unsafe)), ...
    'An OK prefix cannot promote proxy, unavailable or noise-floor-bound values into measurements.');
assert(~any(sixgr.util.isAcceptableSINRStatus(lower(unsafe))));
assert(isequal(size(sixgr.util.isAcceptableSINRStatus(reshape(unsafe(1:12),3,4))),[3 4]));

T = table(statuses, statuses, statuses, ...
    'VariableNames', {'PostEqSINRValueStatus','ReceiverHestSINRValueStatus','MeasuredTrialSINRValueStatus'});
vars = string(T.Properties.VariableNames);
for name = vars(endsWith(vars, "SINRValueStatus"))
    col = string(T.(char(name)));
    assert(isequal(sixgr.util.isAcceptableSINRStatus(col), expected), ...
        "%s must classify through the shared measured-SINR status contract.", name);
end
end

function localAssertControlReferenceStrictUsesSharedContract()
status = ["OK"; "OK_dynamic_range_limited"; "OK_decision_residual_bounded"; "rejected"; ...
    "OK_PROXY";"OK_FALLBACK";"OK_LOWER_BOUND_NOISE_FLOOR"];
n = numel(status);
T = table( ...
    repmat("PASS", n, 1), ...
    false(n, 1), ...
    true(n, 1), ...
    true(n, 1), ...
    true(n, 1), ...
    repmat(32, n, 1), ...
    zeros(n, 1), ...
    ones(n, 1), ...
    repmat(18, n, 1), ...
    status, ...
    repmat(0.01, n, 1), ...
    repmat("OK", n, 1), ...
    true(n, 1), ...
    true(n, 1), ...
    true(n, 1), ...
    'VariableNames', {'Status','Crash','CRCApplicable','DCICrcPass','PDCCHPayloadMatch', ...
    'BitsCompared','BitErrors','CandidatesAttempted','ReceiverHestSINR_dB', ...
    'ReceiverHestSINRValueStatus','NoiseVariance','NoiseVarStatus', ...
    'ChannelEstimateAvailable','ResourceExtractionAvailable','EqualizationAvailable'});

out = sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("PDCCH", T);
assert(all(logical(out.StrictReceiverEvidenceOk(1:3))) && all(logical(out.StrictOk(1:3))), ...
    "PDCCH strict evidence must accept every shared OK* ReceiverHestSINRValueStatus.");
assert(~logical(out.StrictReceiverEvidenceOk(4)) && strcmp(string(out.Status(4)), "FAIL"), ...
    "PDCCH strict evidence must still reject non-OK SINR statuses.");
assert(~any(logical(out.StrictReceiverEvidenceOk(5:end))) && ...
    ~any(logical(out.StrictOk(5:end))), 'Invalid OK-prefixed statuses cannot qualify strict receiver evidence.');
end

function localAssertMeasuredSINRCurveFilterUsesSharedContract()
tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

trialData = struct();
trialData.dl = localTrialTable();
trialData.ul = table();

res = sixgr.analytics.generateMeasuredSINRCurves(tmp, "sinr_status_unit", ...
    "TrialData", trialData, ...
    "ScenarioConfig", struct("global_radio_scope", struct("channel_bandwidth_hz", 20e6)), ...
    "BinCount", 4, ...
    "WriteKPISummary", true, ...
    "UpdateAnchorKPIs", false);

assert(logical(res.Ok), "Measured-SINR curve generation must succeed for status contract fixture.");
summary = res.Tables.Summary;
assert(istable(summary) && height(summary) == 1, ...
    "Focused measured-SINR status fixture should produce one DL summary row.");
assert(double(summary.N_Trials(1)) == 4, ...
    "Measured-SINR filter must include all four OK* statuses and exclude non-OK statuses.");
end

function T = localTrialTable()
status = ["OK"; "OK_dynamic_range_limited"; "OK_decision_residual_bounded"; ...
    "OK_future_estimator_variant"; "unavailable"; "available_system_level_estimate"; ...
    "rejected"; ""; "OK_PROXY"; "OK_FALLBACK"; "OK_SYNTHETIC"; "OK_LOWER_BOUND_NOISE_FLOOR"];
n = numel(status);
sinr = (-2:n-3).';
crcPass = sinr > 0;
T = table( ...
    repmat("DL", n, 1), ...
    (0:n-1).', ...
    sinr, ...
    status, ...
    true(n, 1), ...
    false(n, 1), ...
    false(n, 1), ...
    crcPass, ...
    double(crcPass) .* 1024, ...
    repmat(1024, n, 1), ...
    repmat(1024, n, 1), ...
    double(~crcPass) .* 8, ...
    double(crcPass) .* 1024 ./ 0.5e-3 ./ 1e6, ...
    repmat(1024 ./ 0.5e-3 ./ 1e6, n, 1), ...
    100 + (0:n-1).', ...
    5 + (0:n-1).', ...
    repmat(4, n, 1), ...
    repmat("QPSK", n, 1), ...
    ones(n, 1), ...
    'VariableNames', {'Direction','Slot','PostEqSINR_dB','PostEqSINRValueStatus', ...
    'FinalizedFlag','IsWarmupFrame','FallbackFlag','CRCPass','GoodBits','OfferedBits', ...
    'BitsCompared','BitErrors','Goodput_Mbps','OfferedThroughput_Mbps', ...
    'PropagationDistance_m','LargeScaleSINR_dB','MCS','Modulation','Layers'});
end
