function ok = testProductionTimingCallerMigration()
%TESTPRODUCTIONTIMINGCALLERMIGRATION Active callers use one timing adapter.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
cfg = withCanonicalSchedulerTiming(sixgr.config.defaultConfig());
% This baseline exercises timing migration with the configured basic DCI
% 1_0 search space.  Make the spatial operating point explicit instead of
% inheriting defaultConfig's rank-four study preference, which correctly
% requires DCI 1_1 in production.
cfg.phy.pdsch.numLayers = 1;
cfg.phy.pdsch.nLayers = 1;
cfg.phy.pdsch.numPorts = 1;
cfg.phy.pdsch.nPorts = 1;
cfg.phy.pdsch.dmrs.portSet = 0;
cfg.phy.pdsch.dmrs.DMRSPortSet = 0;

dlGrant = localGrant("DL");
dl = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(cfg, dlGrant);
assert(dl.Valid && dl.K0 == 1 && dl.K1 == 2 && ...
    dl.DataAbsoluteSlot == 1 && dl.FeedbackAbsoluteSlot == 3, ...
    "DL production timing must resolve configured K0/K1 on the exact timeline.");
assert(dl.HARQEnabled && dl.HARQACKRequired, ...
    "An enabled HARQ authority must require a physical DL ACK occasion.");

harqOff = cfg;
harqOff.phy.harq.enable = false;
harqOff.mac.harq.enable = false;
dlWithoutACK = rmfield(dlGrant, "HARQFeedbackSymbolAllocation");
disabledHARQDecision = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(harqOff, dlWithoutACK);
assert(disabledHARQDecision.Valid && disabledHARQDecision.K0 == 1 && ...
    isnan(disabledHARQDecision.K1) && ...
    disabledHARQDecision.FeedbackAbsoluteSlot == int64(-1) && ...
    ~disabledHARQDecision.HARQEnabled && ...
    ~disabledHARQDecision.HARQACKRequired, ...
    "HARQ-off DL grants must resolve K0 without inventing a K1/ACK resource.");

missingAuthority = cfg;
missingAuthority.phy = rmfield(missingAuthority.phy, "harq");
missingAuthority.mac = rmfield(missingAuthority.mac, "harq");
missingAuthorityDecision = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(missingAuthority, dlGrant);
assert(~missingAuthorityDecision.Valid && ...
    missingAuthorityDecision.ReasonCode == ...
        "harq_enable_authority_not_attached", ...
    "Production timing must fail closed when HARQ enablement is absent.");

inconsistentAuthority = cfg;
inconsistentAuthority.phy.harq.enable = false;
inconsistentAuthority.mac.harq.enable = true;
inconsistentAuthorityDecision = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(inconsistentAuthority, dlGrant);
assert(~inconsistentAuthorityDecision.Valid && ...
    inconsistentAuthorityDecision.ReasonCode == ...
        "inconsistent_harq_enable_authority", ...
    "Production timing must reject contradictory PHY/MAC HARQ authority.");

ulGrant = localGrant("UL");
ul = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(cfg, ulGrant);
assert(ul.Valid && ul.K2 == 1 && ul.DataAbsoluteSlot == 1, ...
    "UL production timing must resolve configured K2 and explicit timing advance.");

[k1, helperDecision] = ...
    sixgr.l2.mac.resolveHARQFeedbackK1(cfg, dlGrant);
assert(k1 == 2 && helperDecision.Valid && ...
    helperDecision.Adapter == dl.Adapter, ...
    "The HARQ helper must delegate to the canonical production adapter.");
localAssertError(@() sixgr.l2.mac.resolveHARQFeedbackK1( ...
    0, "DDDSU", 1), ...
    "sixgr:l2:mac:LegacyHARQTimingSignatureRejected");

waveformGrant = sixgr.link.resolveWaveformGrant(cfg, "DL", 0);
assert(waveformGrant.TimingDecision.Valid && ...
    waveformGrant.K0 == 1 && waveformGrant.K1 == 2 && ...
    waveformGrant.ScheduledAbsoluteSlot == 1, ...
    "resolveWaveformGrant/SchedulerBase must freeze the same canonical decision.");

advancedUL = cfg;
advancedUL.phy.pusch.numLayers = 2;
advancedUL.phy.pusch.nLayers = 2;
advancedUL.phy.pusch.numPorts = 2;
advancedUL.phy.pusch.nPorts = 2;
advancedUL.phy.pusch.dmrs.portSet = [0 1];
advancedUL.phy.pusch.dmrs.DMRSPortSet = [0 1];
advancedUL.phy.pusch.transformPrecoding = false;
advancedUL.phy.pdcch.dciFormats = ["1_0", "0_1"];
advancedULGrant = sixgr.link.resolveWaveformGrant(advancedUL, "UL", 0);
assert(advancedULGrant.K2 == 1 && ...
    advancedULGrant.DCI.Format == "DCI_0_1" && ...
    advancedULGrant.DCI.FieldValues.K2 == 1 && ...
    ~isfield(advancedULGrant.DCI.FieldValues, "k2"), ...
    "DCI 0_1 must retain K2 timing lineage without encoding K2 as an unsupported payload field.");
assert(isequal(double(advancedULGrant.DMRSPortSet), [0 1]) && ...
    isequal(double(advancedULGrant.PHYGrant.CodingLayout.DMRSPortSet), [0 1]), ...
    "The scheduled rank must carry an exact immutable per-layer DM-RS port set.");

badIdentity = dlGrant;
badIdentity.ScheduledCCID = 99;
rejectedIdentity = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(cfg, badIdentity);
assert(~rejectedIdentity.Valid && ...
    rejectedIdentity.ReasonCode == "invalid_control_timing_identity", ...
    "A supplied CC identity must be consumed and rejected when unconfigured.");

override = cfg;
override.phy.frameStructure.TimingContext.Policy. ...
    N1PDSCHProcessingTimeSymbols = 9;
override.phy.frameStructure.TimingContext.Policy. ...
    ControlToDataProcessingTimeSymbols.PDSCHToHARQACKN1 = 9;
rejectedOverride = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(override, dlGrant);
assert(~rejectedOverride.Valid && ...
    rejectedOverride.ReasonCode == "invalid_production_timing_policy" && ...
    contains(rejectedOverride.Diagnostic, ...
        "ProductionTimingCapabilityOverride"), ...
    "Caller processing-time overrides must not replace the pinned catalog.");

missingK2 = cfg;
missingK2.phy.frameStructure.TimingContext.Policy.AllowedK2 = [];
missingK2.phy.frameStructure.TimingContext.Policy.K2Rows = struct([]);
dlWithoutK2 = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(missingK2, dlGrant);
ulWithoutK2 = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(missingK2, ulGrant);
assert(dlWithoutK2.Valid && ~ulWithoutK2.Valid && ...
    ulWithoutK2.ReasonCode == "invalid_production_timing_policy", ...
    "Only relations invoked by a production procedure may be required.");

switched = localSwitchedContext(cfg);
switchedGrant = dlGrant;
switchedGrant.ControlAbsoluteSlot = 2;
switchedGrant.SourceBWPID = 1;
switchedGrant.DLBWPID = 1;
switchedGrant.ULBWPID = 0;
switchedGrant.TargetBWPID = 1;
switchDecision = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(switched, switchedGrant);
assert(switchDecision.Valid && switchDecision.SourceBWPID == "1" && ...
    switchDecision.TargetBWPID == "1", ...
    "Production reconstruction must replay attached BWP switch history.");

inactive = cfg;
inactiveGrant = dlGrant;
inactiveGrant.SourceBWPID = 1;
inactiveGrant.DLBWPID = 1;
inactiveGrant.TargetBWPID = 1;
inactiveDecision = sixgr.phy.frame.TimingRelationEngine. ...
    resolveProductionGrant(inactive, inactiveGrant);
assert(~inactiveDecision.Valid, ...
    "An unconfigured/inactive supplied BWP identity must fail closed.");

supportedMu = [0, 1, 2, 3, 5, 6];
expectedN1 = [8, 10, 17, 20, 80, 160];
expectedN2 = [10, 12, 23, 36, 144, 288];
for index = 1:numel(supportedMu)
    row = sixgr.phy.frame.TimingPolicyCatalog. ...
        capability1(supportedMu(index));
    assert(row.PDSCHN1Symbols == expectedN1(index) && ...
        row.PUSCHN2Symbols == expectedN2(index));
    k1Values = sixgr.phy.frame.TimingPolicyCatalog. ...
        defaultK1Values(supportedMu(index));
    assert(~isempty(k1Values) && all(k1Values >= 1));
end
localAssertError(@() ...
    sixgr.phy.frame.TimingPolicyCatalog.capability1(4), ...
    "sixgr:phy:frame:UnsupportedProductionTimingNumerology");

ok = true;
end

function grant = localGrant(direction)
grant = struct( ...
    "Direction", direction, ...
    "ControlAbsoluteSlot", 0, ...
    "ControlSymbolAllocation", [0, 2], ...
    "SymbolAllocation", [0, 14], ...
    "HARQFeedbackSymbolAllocation", [0, 2], ...
    "TimingAdvanceTicks", int64(0), ...
    "HARQProcessID", 3);
end

function cfg = localSwitchedContext(base)
cfg = base;
dl(1) = localBWP(0, "DL", true, 0, 0);
dl(2) = localBWP(1, "DL", false, 1, 1);
ul = localBWP(0, "UL", true, 1, 0);
cfg.phy.bwp.dl = dl;
cfg.phy.bwp.ul = ul;
if isfield(cfg.phy, "frameStructure")
    cfg.phy = rmfield(cfg.phy, "frameStructure");
end
if isfield(cfg.phy, "frame")
    cfg.phy = rmfield(cfg.phy, "frame");
end
cfg = sixgr.phy.frame.FrameRuntimeStateBuilder.attachTimingContext(cfg);
[snapshot, carriers] = ...
    sixgr.phy.frame.FrameRuntimeStateBuilder.build(cfg);
carrier = carriers{1};
dl0 = carrier.configuredBWP(0, "DL");
activation = ...
    sixgr.phy.frame.AbsoluteTime.fromAbsoluteSlotSymbol(2, 0, dl0);
queued = carrier.BWPState.scheduleSwitch("DL", 1, activation, ...
    "IssuedTime", sixgr.phy.frame.AbsoluteTime.fromTicks(0), ...
    "ControlBWPID", 0, ...
    "TriggerSource", "RRC", ...
    "CommandID", "test-production-switch");
assert(queued.Accepted);
carrier.BWPState.applyUntil(activation);
state = snapshot.BWPState(1);
state.ActiveDLBWPID = str2double(carrier.BWPState.ActiveDLBWPID);
state.ActiveULBWPID = str2double(carrier.BWPState.ActiveULBWPID);
state.Epoch = double(carrier.BWPState.Epoch);
state.CurrentTick = carrier.BWPState.CurrentTime.tickValue();
state.PendingCommands = table2struct(carrier.BWPState.pendingTable());
state.History = table2struct(carrier.BWPState.historyTable());
snapshot.BWPState(1) = state;
snapshot.DefaultIdentity.SourceBWPID = 1;
snapshot.DefaultIdentity.DLBWPID = 1;
snapshot.DefaultIdentity.ULBWPID = 0;
cfg.phy.frameStructure.TimingContext = snapshot;
end

function value = localBWP(id, direction, active, controlID, dataID)
value = struct( ...
    "BWPID", id, ...
    "Direction", direction, ...
    "NStartBWP", 0, ...
    "NSizeBWP", 273, ...
    "SCSKHz", 30, ...
    "CyclicPrefix", "normal", ...
    "ActiveInitial", active, ...
    "ControlBWPID", controlID, ...
    "DataBWPID", dataID, ...
    "StateVersion", 0, ...
    "SwitchActivationTick", 0);
end

function localAssertError(fcn, expectedIdentifier)
try
    fcn();
catch cause
    assert(string(cause.identifier) == string(expectedIdentifier), ...
        "Expected '%s'; received '%s': %s", ...
        expectedIdentifier, cause.identifier, cause.message);
    return;
end
error("sixgr:tests:ExpectedErrorNotRaised", ...
    "Expected error '%s' was not raised.", expectedIdentifier);
end
