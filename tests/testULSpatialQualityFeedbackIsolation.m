function sameRankPrecoderQualityIsolation(cfg)
cfg.phy.linkAdaptation.initialSpatialConfirmationReports=1; % First measured point; steady increases remain two-report.
% Equal rank is not sufficient: quality belongs to the executed TPMI too.
% Check the declared pair against the native four-port NR codebook, without
% claiming that these delivery-boundary fixtures are waveform measurements.
assert(~isequal(nrPUSCHCodebook(1,4,0,false),nrPUSCHCodebook(1,4,1,false)));
state=declaredState(cfg);
[state,first]=deliver(state,report("SRS",40,41,1,3));
assert(~first.SchedulerSpatialDecisionDeferred);
changed=report("SRS",45,46,1,12); changed.PMI=1;
[state,selected]=deliver(state,changed);
assert(~selected.SchedulerSpatialDecisionDeferred && selected.PMI==1 && ...
    abs(state.ULLinkAdaptationState{1}.SmoothedCQI-selected.SchedulerResolvedCQI)<1e-12, ...
    'sixgr:test:SameRankPrecoderQualityMixed', ...
    'A new TPMI has a different quality state even if the number of layers is unchanged.');
before=state.ULLinkAdaptationState{1};
old=report("PUSCH-DMRS",50,51,1,2); old.PMI=0;
[state,rejected]=deliver(state,old);
assert(rejected.PMI==0 && rejected.RI==1 && isnan(rejected.MCSIndex) && ...
    rejected.SchedulerSpatialDecisionDeferred && ...
    isequaln(state.ULLinkAdaptationState{1}.SmoothedCQI,before.SmoothedCQI) && ...
    isequaln(state.ULLinkAdaptationState{1}.OLLAUpdateCount,before.OLLAUpdateCount), ...
    'sixgr:test:OldTPMIQualityContaminatedCurrentPoint', ...
    'A later data-quality event cannot relabel the old TPMI as the accepted same-rank precoder.');
end

function qualityPreservesNonzeroOLLA(cfg)
state=declaredState(cfg);
[state,~]=deliver(state,report("SRS",40,41,1,10));
state.ULLinkAdaptationState{1}.DeltaMCS=1.25;
state.ULLinkAdaptationState{1}.OLLAUpdateCount=3;
events={report("SRS",45,46,4,14),report("PUSCH-DMRS",50,51,1,10), ...
    report("SRS",50,51,4,14)};
for k=1:numel(events)
    [state,out]=sixgr.truth.CoupledTruthRuntime.applyDeliveredCSIAdaptationRuntime( ...
        state,events{k},1,'UL',struct());
    assert(state.ULLinkAdaptationState{1}.DeltaMCS==1.25 && ...
        state.ULLinkAdaptationState{1}.OLLAUpdateCount==3 && ...
        ~out.OLLAUpdateAppliedAtThisEvent, ...
        'sixgr:test:QualityResetHARQMargin','Changing quality/spatial state cannot reset a nonzero HARQ-owned margin.');
end
assert(state.ULLinkAdaptationState{1}.SchedulerAcceptedRank==4);
end

