function state = declaredState(cfg)
latest = sixgr.truth.CoupledTruthRuntime.emptyLatestFeedbackRowRuntime();
state = struct('CfgMobility',cfg,'NumUsers',1,'DLSchedulers',{{}}, ...
    'ULSchedulers',{{}},'DLLinkAdaptationState',{{struct()}}, ...
    'ULLinkAdaptationState',{{struct()}}, ...
    'SlotDuration_s',sixgr.time.slotDurationSec(cfg), ...
    'LatestDLFeedback',latest,'LatestULFeedback',latest,'PendingCSITable',table());
end

function value = report(signal,sourceSlot,deliverySlot,rank,cqi)
value = struct('CQI',cqi,'RI',rank,'PMI',0,'CRI',NaN, ...
    'SINR_dB',NaN,'SourceSlot',sourceSlot,'DueSlot',deliverySlot, ...
    'DeliveredSlot',deliverySlot,'ServingCell',1,'SourceSignal',signal, ...
    'ReportIdentity',"declared_boundary_"+signal+"_"+sourceSlot+"_"+deliverySlot);
end

function [state,value] = deliver(state,value)
unchanged = value;
[state,value] = sixgr.truth.CoupledTruthRuntime.applyDeliveredCSIAdaptationRuntime( ...
    state,value,1,'UL',struct());
assert(value.RI == unchanged.RI && isequaln(value.PMI,unchanged.PMI) && ...
    value.SourceSlot == unchanged.SourceSlot && ...
    value.DeliveredSlot == unchanged.DeliveredSlot && ...
    value.SourceSignal == unchanged.SourceSignal, ...
    'sixgr:test:RawFeedbackRelabeled','Preserve the supplied receiver observation and its clocks.');
assert(state.ULLinkAdaptationState{1}.OLLAUpdateCount == 0, ...
    'sixgr:test:QualityChangedHARQOLLA','Only delivered HARQ feedback may update OLLA.');
end

function requireSpatialState(state,accepted,candidate,count)
spatial = state.ULLinkAdaptationState{1};
assert(spatial.SchedulerAcceptedRank == accepted && ...
    spatial.RankIncreaseCandidate == candidate && ...
    spatial.RankIncreaseConfirmationCount == count, ...
    'sixgr:test:QualityReplacedSpatialEvidence', ...
    'Executed-rank quality must not change the accepted rank or pending SRS confirmation.');
end
