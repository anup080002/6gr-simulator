function publicQualityDoesNotRenewSpatialAdmission(cfg)
cfg.phy.linkAdaptation.initialSpatialConfirmationReports=1; % First measured point; steady increases remain two-report.
state=initializedRuntime(cfg);
state=deliverSRSThroughProducer(state,1,45,46);
state.CurrentSlot=50;
state=sixgr.truth.CoupledTruthRuntime.enqueueCSIReportRuntime( ...
    state,1,'UL',declaredPUSCH(50),cfg,table());
state=sixgr.truth.CoupledTruthRuntime.beginSlot( ...
    state,cfg,cfg,1,'UL',1,1,51,100,40);
% Explicit state-boundary fixture: a newer successful sounding exists,
% but has not replaced the accepted spatial decision from source45.
state.LastSuccessfulSRSSlotByUE(1)=50;
state.SRSValidityState(1)="valid";
state.ControlGating.SRSMaxAgeSlots=4;
[~,ue]=sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime( ...
    state,cfg,1,'UL',1);
printSpatialAdmission(ue,"reducer_only_missing_accepted_identity");
% The reducer-only boundary deliberately never publishes an accepted SRS
% identity. Its stale clocks remain visible, but the stricter identity gate
% is the final blocker. It must not authorize a grant from declared RI alone.
assert(ue.FeedbackSourceSlot==50 && ue.FeedbackAgeSlots==1 && ...
    ue.SpatialDecisionSourceSlot==45 && ue.SpatialDecisionAgeSlots==6 && ...
    ~ue.CausalFeedbackUsable && ~ue.SchedulingEligible && ~ue.Active && ...
    isempty(fieldnames(ue.AcceptedSRSSpatialDecision)) && ~ue.AcceptedSRSCausalUsable && ...
    string(ue.AcceptedSRSCausalStatus)=="accepted_srs_spatial_identity_unavailable" && ...
    string(ue.CausalFeedbackStatus)=="accepted_srs_accepted_srs_spatial_identity_unavailable", ...
    'sixgr:test:FreshDataRenewedExpiredSpatialDecision', ...
    'Fresh quality must neither renew stale spatial clocks nor invent accepted identity.');
end

function publicAcceptedQualityDoesNotRenewSpatialAdmission(cfg)
cfg.phy.linkAdaptation.initialSpatialConfirmationReports=1; % First measured point; steady increases remain two-report.
% Full public SRS publisher with declared component receiver inputs, not IQ.
% Its accepted identity is produced normally, never installed by the test.
state=initializedRuntime(cfg);
state=deliverSRSThroughProducer(state,1,45,46,true);
accepted=state.LatestULFeedback.AcceptedSRSSpatialDecision;
assert(accepted.ProducerSlot==45 && accepted.AvailableSlot==46 && ...
    accepted.RI==1 && accepted.PMI==0 && accepted.MeasurementClockDomain=="slot_only");
% A first rank-four candidate refreshes raw sounding, but normal two-report
% confirmation retains the earlier accepted tuple and its original clocks.
state=deliverSRSThroughProducer(state,4,50,51,true);
assert(isequaln(state.LatestULFeedback.AcceptedSRSSpatialDecision,accepted) && ...
    state.LastSuccessfulSRSSlotByUE(1)==50);
state=sixgr.truth.CoupledTruthRuntime.beginSlot( ...
    state,cfg,cfg,1,'UL',1,1,51,100,40);
state=sixgr.truth.CoupledTruthRuntime.enqueueCSIReportRuntime( ...
    state,1,'UL',declaredPUSCH(50),cfg,table());
state.ControlGating.SRSMaxAgeSlots=4; % Explicit age-boundary fixture.
[~,ue]=sixgr.truth.CoupledTruthRuntime.buildSchedulerUEStateRuntime( ...
    state,cfg,1,'UL',1);
printSpatialAdmission(ue,"published_accepted_identity_stale");
assert(ue.FeedbackSourceSlot==50 && ue.FeedbackAgeSlots==1 && ...
    ue.SpatialDecisionSourceSlot==45 && ue.SpatialDecisionAgeSlots==6 && ...
    ue.QualityMeasurementSourceSlot==50 && ue.QualityMeasurementDeliveredSlot==51 && ...
    ue.SRSCausalUsable && ue.SRSCausalAgeSlots==1 && ...
    isequaln(ue.AcceptedSRSSpatialDecision,accepted) && ...
    ~ue.AcceptedSRSCausalUsable && string(ue.AcceptedSRSCausalStatus)=="stale" && ...
    ~ue.CausalFeedbackUsable && ~ue.SchedulingEligible && ~ue.Active && ...
    string(ue.CausalFeedbackStatus)=="accepted_srs_stale", ...
    'sixgr:test:FreshDataRenewedExpiredAcceptedSpatialDecision', ...
    'Fresh raw sounding and data quality cannot renew an expired accepted SRS identity.');
end

