function state = initializedRuntime(cfg)
% Initialize production value state only. No advanceSlot, waveform TX/RX,
% performance outputs or 100-slot execution occurs in this ownership test.
multi = struct('Enabled',true,'NumUsers',1,'RNTIStart',double(cfg.phy.pusch.RNTI), ...
    'ExecutionModel','slot_coupled_truth');
state = sixgr.truth.CoupledTruthRuntime.initialize(cfg,tempname,multi,struct(),100);
state.CurrentServingIdx(:) = 1;
assert(state.CSIFeedbackSlots == 1 && state.NumUsers == 1, ...
    'This regression retains the installed H4 feedback delay and one-UE scope.');
end

function state = deliverSRSThroughProducer(state,rank,sourceSlot,deliverySlot,publishIdentity)
% Authored receiver-completion boundary, never exported as measured IQ.
% Use the production clock validator and SRS consumer, not a re-created
% latest-feedback struct. All spatial/power inputs are explicit fixtures.
if nargin<5, publishIdentity=false; end
row = struct('Slot',sourceSlot,'ServingCell',1,'SINR_dB',20,'WidebandCQI',10, ...
    'RIEstimate',rank,'TPMIEstimate',0,'SRSBandwidthCoverageStatus',"full_band", ...
    'SRSBandwidthFraction',272/273,'PredictedPUSCHMinimumLayerSINR_dB',20, ...
    'PredictedPUSCHPostEqSINRSource', ...
        "receiver_measured_srs_reference_power_selected_ri_tpmi_mmse_layer_prediction", ...
    'PredictedPUSCHPostEqSINRValueRole', ...
        "power_plane_calibrated_predicted_pusch_data_channel_scheduling_input", ...
    'PredictedPUSCHPostEqSINRValueStatus',"PASS", ...
    'PredictedPUSCHPostEqSINRAnchor_dB',20, ...
    'PredictedPUSCHPostEqSINRAnchorSource',"measured_ul_srs_pilot_reconstruction_sinr", ...
    'PredictedPUSCHPostEqSINRPowerReferencePlane',"receiver_srs_resource_elements_after_ofdm_demodulation", ...
    'PredictedPUSCHReferenceSignalPower',1,'PredictedPUSCHDisturbancePower',.01, ...
    'PUSCHToSRSReferenceEnergyRatio',1,'PUSCHToSRSReferenceEnergySource', ...
        "normalized_fixed_snr_unit_grid_reference_no_device_power_scaling");
carrier = sixgr.phy.grid.makeCarrier(state.CfgMobility);
ofdm = nrOFDMInfo(carrier);
fs = ofdm.SampleRate;
row.ObservationStartSample = round((sourceSlot-1)*state.SlotDuration_s*fs);
row.ObservationEndSampleExclusive = round(sourceSlot*state.SlotDuration_s*fs);
row.ObservationSampleRateHz = fs;
row.ObservationCompletionTime_s = row.ObservationEndSampleExclusive/fs;
row.ObservationCoverageSource = "complete_contiguous_received_sample_buffer";
row.ObservationDeliverySlot = deliverySlot;
row.ObservationDeliveryTime_s = (deliverySlot-1)*state.SlotDuration_s;
row.ObservationDeliverySource = "canonical_slot_start_after_complete_received_window";
state.CurrentSlot = deliverySlot;
if publishIdentity
    % Declared completion inputs at the public value-state publisher. These
    % flags are test operands, not new waveform evidence or a shared clock.
    row.DetectionAttempted=true; row.DetectionSuccess=true;
    row.ResourceExtractionAttempted=true; row.ResourceExtractionAvailable=true;
    row.ChannelEstimateAttempted=true; row.SRSChannelEstimateAvailable=true;
    row.SRSRuntimeEvidenceUsable=true; row.Crash=false; row.ProxyUsed=false;
    row.SRSReceiveTimingOffset_samples=NaN;
    state=sixgr.truth.CoupledTruthRuntime.applySRSTrial(state,1,struct2table(row,'AsArray',true));
else
    state = sixgr.truth.CoupledTruthRuntime.updateLatestULFeedbackFromSRSTrialRuntime( ...
        state,1,row,sourceSlot);
end
end

function row = declaredPUSCH(slot)
