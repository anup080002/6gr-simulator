function ok = testULSpatialQualityFeedbackIsolation()
% Declared delivery-boundary regression, NOT a waveform or BLER campaign.
% Reproduce the SRS45 / PUSCH50 / SRS50 event-order defect observed in H4.
% TS 38.214 6.1.1.1 binds the scheduled PUSCH spatial operating point to
% SRI/TPMI/layers. A data receiver's executed layer count is not a new SRS
% rank recommendation. The two-report hysteresis is SixGR YAML policy,
% not a mandated 3GPP algorithm; keep that policy and its count unchanged.
setup6GRSimToolkit('Verbose',false);
source = sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_gate.yaml');
cfg = sixgr.lls6g.buildInternalConfig(source,tempname);
cfg.phy.linkAdaptation.initialSpatialConfirmationReports=2; % Explicit two-report initial fixture.
assert(cfg.phy.pusch.numLayers == 1 && cfg.phy.pusch.maxLayers == 4 && ...
    cfg.phy.linkAdaptation.rankIncreaseConfirmationReports == 2);
cases = {@qualityBetweenSoundings, @qualityAfterRankTransition, ...
    @independentSourceClocks, @outageDoesNotRecommendRank, ...
    @duplicateQualityDoesNotConfirmRank, @publicQueueBeforeSRS, ...
    @publicQueueAfterSRS, @publicAlreadyDueQuality, ...
    @candidateQualityDoesNotPolluteCurrentRank, ...
    @sameRankPrecoderQualityIsolation, @publicQualityPreservesSpatialAge, ...
    @qualityPreservesNonzeroOLLA, @fixedRankMismatchPreservesQuality, ...
    @publicQualityDoesNotRenewSpatialAdmission, ...
    @publicAcceptedQualityDoesNotRenewSpatialAdmission};
failures = cell(0,1);
for k = 1:numel(cases)
    try
        cases{k}(cfg);
        fprintf('UL_SPATIAL_QUALITY_CASE_PASS %s waveform_qualification=0\n', ...
            func2str(cases{k}));
    catch cause
        fprintf('UL_SPATIAL_QUALITY_CASE_FAIL %s %s: %s\n', ...
            func2str(cases{k}),cause.identifier,cause.message);
        failures{end+1,1} = cause; %#ok<AGROW>
    end
end
if ~isempty(failures)
    combined = MException('sixgr:test:ULSpatialQualityIsolationFailed', ...
        '%d/%d receiver-delivery boundary cases failed.',numel(failures),numel(cases));
    for k = 1:numel(failures), combined = addCause(combined,failures{k}); end
    throw(combined);
end
fprintf('UL_SPATIAL_QUALITY_ISOLATION_PASS cases=%d waveform_qualification=0\n',numel(cases));
ok = true;
end

function qualityBetweenSoundings(cfg)
state = pendingSRS(cfg);
[state,quality] = deliver(state,report("PUSCH-DMRS",50,51,1,10));
requireSpatialState(state,1,4,1);
assert(quality.RI == 1 && isfinite(quality.MCSIndex), ...
    'sixgr:test:DataQualityNotApplied', ...
    'Matching executed-rank quality may update MCS without becoming a spatial report.');
[state,confirmed] = deliver(state,report("SRS",50,51,4,10));
assert(state.ULLinkAdaptationState{1}.SchedulerAcceptedRank == 4 && ...
    ~confirmed.SchedulerSpatialDecisionDeferred && confirmed.RI == 4, ...
    'sixgr:test:InterleavedQualityResetSRS', ...
    'Two independent SRS recommendations must still confirm rank with PUSCH quality between them.');
end

function qualityAfterRankTransition(cfg)
state = pendingSRS(cfg);
[state,confirmed] = deliver(state,report("SRS",50,51,4,10));
assert(~confirmed.SchedulerSpatialDecisionDeferred && ...
    state.ULLinkAdaptationState{1}.SchedulerAcceptedRank == 4);
before = state.ULLinkAdaptationState{1};
[state,oldRank] = deliver(state,report("PUSCH-DMRS",50,51,1,2));
after = state.ULLinkAdaptationState{1};
assert(after.SchedulerAcceptedRank == 4 && oldRank.RI == 1 && ...
    isnan(oldRank.MCSIndex) && oldRank.SchedulerSpatialDecisionDeferred, ...
    'sixgr:test:ExecutedRankRolledBackSRS', ...
    'Delayed rank-one quality cannot roll back a confirmed rank-four operating point.');
assert(isequaln(after.SmoothedCQI,before.SmoothedCQI) && ...
    isequaln(after.OLLAUpdateCount,before.OLLAUpdateCount), ...
    'sixgr:test:OldRankQualityContaminatedNewRank', ...
    'Reject old-rank quality before it changes the current CQI filter or OLLA.');
end

function independentSourceClocks(cfg)
state = pendingSRS(cfg);
[state,~] = deliver(state,report("PUSCH-DMRS",50,51,1,10));
% Source 49 is older than the data source, but newer than the last SRS45.
% Delivery remains monotonic. Data freshness must not erase SRS history.
[state,confirmed] = deliver(state,report("SRS",49,52,4,10));
assert(state.ULLinkAdaptationState{1}.SchedulerAcceptedRank == 4 && ...
    ~confirmed.SchedulerSpatialDecisionDeferred, ...
    'sixgr:test:DataClockRejectedNewSRS', ...
    'Deduplicate and age spatial feedback by its own source history.');
before = state;
[state,duplicate] = deliver(state,report("SRS",49,52,4,10));
assert(isequaln(state,before) && duplicate.SchedulerSpatialDecisionDeferred, ...
    'sixgr:test:DuplicateSpatialEventChangedState', ...
    'An identical SRS delivery must not supply another confirmation or refresh its age.');
end

