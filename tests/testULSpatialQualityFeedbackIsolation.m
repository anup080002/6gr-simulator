function candidateQualityDoesNotPolluteCurrentRank(cfg)
cfg.phy.linkAdaptation.initialSpatialConfirmationReports=1; % First measured point; steady increases remain two-report.
state = declaredState(cfg);
[state,current] = deliver(state,report("SRS",40,41,1,3));
assert(~current.SchedulerSpatialDecisionDeferred && ...
    state.ULLinkAdaptationState{1}.SchedulerAcceptedRank == 1);
before = state.ULLinkAdaptationState{1};
[state,candidate] = deliver(state,report("SRS",45,46,4,14));
requireSpatialState(state,1,4,1);
assert(candidate.CQI == 14 && candidate.RI == 4 && ...
    candidate.SchedulerSpatialDecisionDeferred && isnan(candidate.MCSIndex));
assert(isequaln(state.ULLinkAdaptationState{1}.SmoothedCQI,before.SmoothedCQI), ...
    'sixgr:test:UnconfirmedRankPollutedCurrentCQI', ...
    'Retain candidate-rank quality separately; it cannot enter the current-rank CQI filter.');
[state,quality] = deliver(state,report("PUSCH-DMRS",50,51,1,3));
requireSpatialState(state,1,4,1);
assert(~quality.SchedulerSpatialDecisionDeferred && ...
    abs(state.ULLinkAdaptationState{1}.SmoothedCQI-before.SmoothedCQI) < 1e-12);
[state,confirmed] = deliver(state,report("SRS",50,51,4,14));
assert(~confirmed.SchedulerSpatialDecisionDeferred && ...
    state.ULLinkAdaptationState{1}.SchedulerAcceptedRank == 4 && ...
    abs(state.ULLinkAdaptationState{1}.SmoothedCQI-confirmed.SchedulerResolvedCQI) < 1e-12, ...
    'sixgr:test:RankTransitionMixedOperatingPointQuality', ...
    'The confirmed rank-four filter must use its aged CQI, not old rank-one CQI.');
fprintf('UL_QUALITY_FILTER raw=%g aged=%g filtered=%g\n',confirmed.CQI, ...
    confirmed.SchedulerResolvedCQI,state.ULLinkAdaptationState{1}.SmoothedCQI);
end

