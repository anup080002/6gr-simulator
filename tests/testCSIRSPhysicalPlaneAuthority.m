function ok=testCSIRSPhysicalPlaneAuthority()
% Actual native CSI reception: internal samples do not prove a connector.
% Declared amplitude units exercise numerical conversion, not calibrated
% hardware or TS 38.133 accuracy. No channel/RF reference enters estimation.
setup6GRSimToolkit('Verbose',false);
saved=rng; cleanup=onCleanup(@()rng(saved)); %#ok<NASGU>
carrier=nrCarrierConfig('NSizeGrid',24,'SubcarrierSpacing',30,'NCellID',17,'NSlot',1);
cfg.run.strictMode=true; cfg.channel.model='AWGN';
cfg.phy.csirs=struct('enable',true,'period_slots',5,'offset_slots',1, ...
    'numResources',1,'nPorts',4,'density','one','resourceIDs',11, ...
    'rowNumbers',4,'symbolLocationsByResource',3, ...
    'subcarrierLocationsByResource',0,'rbOffsetsByResource',0, ...
    'numRBsByResource',24,'runtimeChannelEstimator','nr_channel_estimate');
cfg.phy.mimo=struct('strict',true,'measurementMaxAgeSlots',8);
cfg.phy.csi.reportConfiguration=struct('Ports',4);
cfg.phy.rx.cfoCorrectionEnabled=false;
cfg.lls6g.userContext=struct('RuntimeUEIndex',1,'RuntimeCurrentSlot',2);
cfg.integration=struct('run_mode','FIXED_SNR_SWEEP','configured_snr_is_link_authority',true);
cfg.powerAndRF.bsTxPower_dBm=0; % Declared component budget, not hardware calibration.
cfg.powerAndRF.downlinkPowerNormalizationPolicy='active_ofdm_total_power';
[indices,symbols]=sixgr.phy.refsig.csirs(carrier,cfg);
grid=nrResourceGrid(carrier,4); grid(indices)=symbols;
[waveform,ofdm]=nrOFDMModulate(carrier,grid,'Windowing',0);
failures=strings(0,1);
for unit=["normalized_complex_baseband","sqrt_mW"]
    declared=cfg;
    if unit=="sqrt_mW"
        declared.integration=struct('run_mode','GEOMETRY_NETWORK', ...
            'configured_snr_is_link_authority',false);
    end
    try
        [input,declared.lls6g.runtimePowerContext]=sixgr.rf.applyPowerContext( ...
            waveform,declared,'DL',struct('OFDMInfo',ofdm),'ApplyPA',false);
        assert(sixgr.rf.appliedWaveformAmplitudeUnit( ...
            declared,declared.lls6g.runtimePowerContext)==unit);
        rx=sixgr.phy.refsig.receiveCSIRSWaveform( ...
            carrier,declared,input,input,[0 0],struct());
        obs=rx.CSIRSObservation;
        assert(obs.PhysicalMeasurementReferencePlane== ...
            "supplied_receive_columns_pre_RX_front_end", ...
            'test:CSIUnsupportedConnectorClaim', ...
            'Supplied pre-front-end columns do not prove installed elements or a UE antenna connector.');
        assert(~contains(obs.PhysicalMeasurementReferencePlane,"connector"));
        if unit=="sqrt_mW"
            assert(obs.PowerReferencePlane==obs.PhysicalMeasurementReferencePlane && ...
                isfinite(obs.MeasurementRSRP_dBm));
        else
            assert(obs.PowerReferencePlane=="normalized_fixed_esn0_unit_occupied_re_es" && ...
                isnan(obs.MeasurementRSRP_dBm) && ...
                isfinite(obs.MeasurementRSRP_dB_re_UnitOccupiedRE_Es));
        end
        % Independently supplied upstream measurement amplitude must not
        % change the practical post-front-end estimate or its feedback state.
        half=sixgr.phy.refsig.receiveCSIRSWaveform( ...
            carrier,declared,input,.5*input,[0 0],struct());
        assert(isequaln(rx.CSIMeasurementState,half.CSIMeasurementState) && ...
            isequaln(rx.CSIChannelEstimateForPMI,half.CSIChannelEstimateForPMI));
        field="MeasurementRSRP_dBm";
        if unit=="normalized_complex_baseband", field="MeasurementRSRP_dB_re_UnitOccupiedRE_Es"; end
        assert(abs(half.CSIRSObservation.(field)-obs.(field)-20*log10(.5))<1e-9);
        received=struct('OFDMGrid',rx.RxGrid,'OFDMInfo',rx.ReceiverOFDMInfo);
        options=struct('PhysicalMeasurementGrid',rx.RxGrid, ...
            'PhysicalMeasurementOFDMInfo',rx.ReceiverOFDMInfo, ...
            'PhysicalMeasurementGridStatus',"available_declared_component_grid", ...
            'PhysicalMeasurementReferencePlane',"UE_antenna_connector_hardware_qualified");
        claimed=sixgr.phy.refsig.receiveCSIRSFromGrid(carrier,declared,received,options);
        assert(claimed.CSIRSObservation.PhysicalMeasurementDeclaredReferencePlane== ...
            options.PhysicalMeasurementReferencePlane && ...
            claimed.CSIRSObservation.PhysicalMeasurementReferencePlane== ...
            "supplied_receive_columns_pre_RX_front_end" && ...
            isequaln(claimed.CSIRSObservation.(field),obs.(field)), ...
            'test:CSIPlaneFreeTextAuthority','Free text cannot upgrade actual column or power authority.');
        direct=sixgr.phy.refsig.receiveCSIRSFromGrid(carrier,declared,received);
        assert(direct.CSIRSObservation.PhysicalMeasurementReferencePlane== ...
            "supplied_receive_grid_columns_no_composite_front_end" && ...
            isequaln(direct.CSIRSObservation.(field),obs.(field)), ...
            'test:CSIPlaneDisabledRFAuthority','No RF impairment does not establish a connector.');
        fprintf('CSI_PHYSICAL_PLANE_AUTHORITY_PASS unit=%s hardware_qualified=0\n',unit);
    catch cause
        failures(end+1)=unit+": "+string(cause.identifier)+" "+string(cause.message); %#ok<AGROW>
        fprintf('CSI_PHYSICAL_PLANE_AUTHORITY_FAIL %s\n',failures(end));
    end
end
assert(isempty(failures),'test:CSIPhysicalPlaneAuthority','%s',strjoin(failures,newline));
assert(isequal(saved,rng),'test:CSIPlaneRNG','Receiver-only tests must not alter global RNG.');
ok=true;
end
