function ok = testMIMOPhase07FailClosedRunner()
%TESTMIMOPHASE07FAILCLOSEDRUNNER Prevent incomplete evidence promotion.

setup6GRSimToolkit("Verbose",false);
outputDir = fullfile(tempdir,"sixgr_phase07_fail_closed_runner");
if ~isfolder(outputDir)
    mkdir(outputDir);
end
result = sixgr.phy.mimo.runMIMOCSIBeamformingPhaseValidation( ...
    VectorRoot=fullfile(pwd,"tests","vectors","mimo"), ...
    OutputDir=outputDir,SeedList=[11 23 47 89], ...
    ConfidenceLevel=.95,Strict=true);

assert(~result.Passed, ...
    "Incomplete Phase-07 evidence must not pass qualification.");
assert(~result.ContractedArtifactsGenerated, ...
    "Fail-closed runner must not claim contracted artifacts were generated.");
assert(any(strlength(result.MandatoryTestsMissing) > 0), ...
    "Missing mandatory production tests must remain explicit.");
assert(any(strlength(result.MissingIndependentMatrixProfiles) > 0), ...
    "Missing independent codebook matrix packs must remain explicit.");
assert(isfile(result.GateReport), ...
    "Fail-closed runner must write its bounded gate report.");

gate = readtable(result.GateReport,TextType="string");
assert(any(gate.Gate == "independent_vector_pack" & gate.Passed), ...
    "Executed independent-vector evidence must remain visible.");
assert(any(gate.Gate == "independent_codebook_matrix_packs" & ~gate.Passed), ...
    "Missing independent matrix evidence must block qualification.");
assert(~any(isfile(fullfile(outputDir, ...
    ["mimo_run_manifest.csv","mimo_bler_curve.csv"]))), ...
    "Fail-closed runner must not create contracted truth artifacts.");
ok = true;
end
