function ok = testKPIULGoodputNotCopiedFromDL()
%TESTKPIULGOODPUTNOTCOPIEDFROMDL Reproduce AUD-KPI-UL-GOODPUT copy bug.

setup6GRSimToolkit("Verbose", false);

raw = localRawFixture();
out = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw, ...
    "RunId", "kpi_copy_regression", ...
    "ScenarioName", "unit_fixture");

summary = out.SummaryAliases;
assert(abs(double(summary.Goodput_UL_max_Mbps(1)) - 7.952) < 1e-9, ...
    "Goodput_UL_max_Mbps must equal raw UL max Goodput_Mbps, not DL.");
assert(abs(double(summary.Goodput_DL_max_Mbps(1)) - 40.137091) < 1e-9, ...
    "Goodput_DL_max_Mbps must equal raw DL max Goodput_Mbps.");
assert(logical(out.KnownBugRegression.BugPrevented(1)), ...
    "Known DL-to-UL goodput copy bug must be prevented.");

badSummary = summary;
badSummary.Goodput_UL_max_Mbps(1) = 40.137091;
ulMetrics = localMetrics(raw.UL, "UL");
dlMetrics = localMetrics(raw.DL, "DL");
badGuard = sixgr.kpi.guardNoULGoodputCopiedFromDL(badSummary, ulMetrics, dlMetrics);
assert(logical(badGuard.BugDetected(1)) && ~logical(badGuard.BugPrevented(1)), ...
    "Guard must detect the audited bad exported UL value copied from DL.");

ok = true;
end

function raw = localRawFixture()
raw = struct();
raw.UL = table( ...
    repmat("UL", 2, 1), [7.952; 0], [true; false], [0; 120], [7952; 8000], ...
    [7952; 8000], [7952; 0], [1; 2], [1; 2], ["ul_tb_1"; "ul_tb_2"], [0; 0], [0; 0], [0; 0], ...
    [1; 1], [1; 2], ...
    'VariableNames', {'Direction','Goodput_Mbps','CRCPass','BitErrors','BitsCompared', ...
    'TBSize_bits','GoodBits','Frame','Slot','TransportBlockId','HARQProcessId','RV','NDI', ...
    'AirInterfaceObservation_ms','TrialId'});
raw.DL = table( ...
    repmat("DL", 2, 1), [40.137091; 1.0], [true; false], [0; 64], [40137; 40000], ...
    [40137; 40000], [40137; 0], [1; 2], [1; 2], ["dl_tb_1"; "dl_tb_2"], [0; 0], [0; 0], [0; 0], ...
    [1; 1], [1; 2], ...
    'VariableNames', {'Direction','Goodput_Mbps','CRCPass','BitErrors','BitsCompared', ...
    'TBSize_bits','GoodBits','Frame','Slot','TransportBlockId','HARQProcessId','RV','NDI', ...
    'AirInterfaceObservation_ms','TrialId'});
end

function metrics = localMetrics(T, direction)
raw = struct();
raw.(direction) = T;
if direction == "UL"
    raw.DL = table();
else
    raw.UL = table();
end
out = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw);
if direction == "UL"
    metrics = struct("Direction","UL", "GoodputMax_Mbps",double(out.SummaryAliases.Goodput_UL_max_Mbps), ...
        "SourceRowsHash",string(out.SummaryAliases.ULSourceRowsHash), "SourceTablePath","ul_pusch_trials");
else
    metrics = struct("Direction","DL", "GoodputMax_Mbps",double(out.SummaryAliases.Goodput_DL_max_Mbps), ...
        "SourceRowsHash",string(out.SummaryAliases.DLSourceRowsHash), "SourceTablePath","dl_pdsch_trials");
end
end
