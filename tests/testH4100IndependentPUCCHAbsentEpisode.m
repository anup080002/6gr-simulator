function ok=testH4100IndependentPUCCHAbsentEpisode()
% Actual installed 64-RX H0 episode, not a statistical campaign.
% No transmitted report, pilot, waveform, TX RF or desired channel exists.
setup6GRSimToolkit('Verbose',false);
scenario='simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_adaptation.yaml';
source=sixgr.lls6g.config.loadScenarioConfig(scenario);
folder=fullfile(pwd,'results','lls','h4_absent_pucch', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
assert(~isfolder(folder),'test:EvidenceExists'); mkdir(folder);
cfg=sixgr.lls6g.buildInternalConfig(source,folder);
cfg=sixgr.truth.attachFixedLinkRuntimeAntennaContext(cfg,1,1);
cfg=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,19);
ue=struct('UEID',1,'RNTI',cfg.phy.pdsch.RNTI,'ServingCell',1, ...
    'PUCCHCell',1,'ComponentCarrier',cfg.phy.frame.DefaultIdentity.ScheduledCCID, ...
    'ActiveULBWP',cfg.phy.frame.DefaultIdentity.ULBWPID);
rrc=sixgr.phy.pucch.PUCCHConfigBuilder.receiverConfiguration(cfg,ue);
installed=sixgr.phy.mimo.CSIReportConfiguration( ...
    cfg.phy.csi.reportConfiguration,cfg.phy.csi.reportConfiguration.Epoch);
obligation=struct('ObservationID',"H4-absent-combined-component", ...
    'ConfigurationEpoch',rrc.ConfigurationEpoch,'HARQBitCount',2,'SRBitCount',1, ...
    'PriorityIndex',0,'CSIReportConfigID',installed.ReportConfigID, ...
    'CSIConfigurationEpoch',installed.Epoch);
context=sixgr.truth.buildConfiguredPUCCHReceiveContext(obligation,installed);
identity=struct('ObservationID',obligation.ObservationID,'ResourceID',10, ...
    'RNTI',ue.RNTI,'AbsoluteSlot0',18,'Source',"declared_installed_H4_obligation", ...
    'TimingSource',"configured_special_slot",'ResourceSelectionProcedure',"dynamic_harq_csi");
assignment=sixgr.phy.pucch.PUCCHReceptionAssignment(identity,rrc,context);
design=struct('EpisodeID',"H4-combined-independent-H0",'UEIndex',1, ...
    'ServingCell',1,'ChannelSeed',5101361,'NoiseSeed',5101362, ...
    'GuardSamples',256,'SignalPresent',false);
emptyTX=struct([]);

% Invalid configuration must fail before creating a physical evidence path.
reject=@(c,a,x,t,d,n) localReject(c,a,x,t,d,fullfile(folder,n));
bad=design; bad.SignalPresent=true;
reject(cfg,assignment,context,emptyTX,bad,'missing_tx');
reject(cfg,assignment,context,struct(),design,'hidden_tx_in_h0');
bad=design; bad.UEIndex=2;
reject(cfg,assignment,context,emptyTX,bad,'wrong_endpoint');
bad=design; bad.UnspecifiedPolicy=true;
reject(cfg,assignment,context,emptyTX,bad,'undeclared_policy');
badCfg=cfg; badCfg.integration.run_mode='LINK_BUDGET';
reject(badCfg,assignment,context,emptyTX,design,'wrong_power_authority');
badCfg=cfg; badCfg.lls6g.userContext=rmfield(badCfg.lls6g.userContext,'RuntimeUEIndex');
reject(badCfg,assignment,context,emptyTX,design,'missing_antenna_owner');
badObligation=obligation; badObligation.HARQBitCount=1;
wrongContext=sixgr.truth.buildConfiguredPUCCHReceiveContext(badObligation,installed);
reject(cfg,assignment,wrongContext,emptyTX,design,'wrong_frozen_context');

episode=sixgr.link.runIndependentPUCCHReceiverEpisode( ...
    cfg,assignment,context,emptyTX,design,fullfile(folder,'physical'));
rx=episode.Receiver;
accepted=rx.ReceiverUsable && ~rx.DTX && (~rx.CRCApplicable || rx.CRCPassed);
falseACK=rx.HARQObservationValid && rx.ObservedHARQACKBitCount>0;
row=table(false,episode.Execution.TxDimensions,episode.Execution.RxDimensions, ...
    rx.DetectionMetric,rx.DetectionThreshold,rx.DTX,rx.CRCApplicable,rx.CRCPassed, ...
    accepted,falseACK,rx.HARQObservationValid,false, ...
    'VariableNames',{'SignalPresent','TxDimensions','RxDimensions','DetectionMetric', ...
    'DetectionThreshold','DTX','CRCApplicable','CRCPassed','FalseAcceptance', ...
    'FalseACKEpisode','HARQObservationValid','StatisticallyQualified'});
sixgr.util.csvWriteTable(fullfile(folder,'receiver_event.csv'),row,'PreserveSchema',true);
disp(row);
assert(~episode.Execution.TransmitterExecuted && ~episode.Execution.DesiredChannelExecuted && ...
    episode.Execution.TxDimensions==0 && episode.Execution.RxDimensions==64 && ...
    isempty(fieldnames(episode.TXReplay)) && isempty(fieldnames(episode.ChannelReplay)));
assert(~isfile(fullfile(folder,'physical','transmitter_reference.mat')) && ...
    height(episode.RFMeasurements)==1 && episode.RXReplay.ADCQuantizationApplied && ...
    episode.RXReplay.PhaseNoiseApplied && episode.RXReplay.TimingOffsetApplied);
assert(episode.RFMeasurements.RunId==design.EpisodeID && ...
    startsWith(episode.RFMeasurements.TrialId,design.EpisodeID+"/rx/UL/samples_") && ...
    ~episode.RFMeasurements.SignalPresent);
assert(rx.DTX && ~accepted && ~falseACK && ~rx.HARQObservationValid, ...
    'test:H4AbsentPUCCHFalseAcceptance', ...
    'Retain an actual false acceptance; do not tune the detector or replace samples.');
assert(episode.Events.FalseAcceptanceEpisode==0 && episode.Events.FalseACKEpisode==0 && ...
    episode.Events.IndependentWaveformCount==1 && ...
    isnan(episode.Events.CompleteUCIErrorEpisode) && ...
    ~episode.Events.HARQBitsAreIndependentTrials && ~episode.Events.StatisticallyQualified);
fprintf('H4_ABSENT_PUCCH_PASS independent_episodes=1 statistical_qualification=0\n');
ok=true;
end

function localReject(cfg,assignment,context,tx,design,folder)
caught=false;
try
    sixgr.link.runIndependentPUCCHReceiverEpisode(cfg,assignment,context,tx,design,folder);
catch err
    assert(strcmp(err.identifier,'sixgr:link:InvalidPUCCHReceiverEpisode'), ...
        'test:UnexpectedPUCCHEpisodeError','Unexpected guard error: %s',err.getReport());
    caught=true;
end
assert(caught && ~isfolder(folder),'test:InvalidPUCCHEpisodeExecuted');
end
