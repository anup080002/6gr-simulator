function ok = testLLSCoupledTruthLiveHeavyRefreshThrottle()
%TESTLLSCOUPLEDTRUTHLIVEHEAVYREFRESHTHROTTLE Ensure heavy live refreshes are not repeated per chunk.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

baseScenario = fullfile(pwd, "simulator", "configs", "scenarios", "lls_mimo4x4_multiuser_beamformed_awgn_validation.yaml");
scenarioPath = fullfile(tmp, "lls_coupled_truth_live_refresh_throttle.yaml");
fid = fopen(scenarioPath, "w");
fprintf(fid, "%s", ['{' ...
    '"inherits":["' strrep(baseScenario, '\', '\\') '"],' ...
    '"meta":{"scenario_id":"lls_coupled_truth_live_refresh_throttle","description":"coupled truth live refresh throttle regression","version":"1","owner":"test","maturity_tag":"regression"},' ...
    '"simulation":{"link_direction":"both","n_frames":1,"n_slots":10,"monte_carlo_iterations":1,"random_seed":29,"snr_db":30,"snr_sweep_offsets_db":[0]},' ...
    '"run_control":{"total_slots":10,"warmup_slots":0,"measurement_slots":10,"total_time_ms":5,"warmup_time_ms":0,"measurement_time_ms":5,"batch_size_links":1,"num_workers":1},' ...
    '"users":{"enabled":true,"n_users":4,"rnti_start":501,"seed_stride":19,' ...
    '"execution_model":"slot_coupled_truth","beam_selection_strategy":"fixed_first_beam","save_user_tables":true},' ...
    '"control_gating":{"pbch_required":false,"prach_required":false,"pdcch_required":false,"srs_required":false,"srs_max_age_slots":1,"trs_required":false,"trs_max_age_slots":1},' ...
    '"sweeps_and_matrix":{"snr_sweep":{"enabled":false,"values_db":[]}},' ...
    '"output":{"save_figures":false,"save_mat":false,"save_png":false,"profile":"lls_coupled_truth_live_refresh_throttle",' ...
    '"live_publish_frame_interval":1,"live_heavy_refresh_interval_frames":5}}']);
fclose(fid);

scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));
slotDuration_s = max(eps, double(sixgr.util.structGet(cfg, "phy.numerology.slotDuration_ms", 0.5)) / 1e3);
opt = struct( ...
    "LinkDuration_s", max(double(cfg.run.totalSlots) * slotDuration_s, slotDuration_s), ...
    "LinkMaxSimFrames", double(cfg.run.totalSlots), ...
    "LinkSNR_dB", double(cfg.channel.snr_dB), ...
    "LinkSNRGrid_dB", double(cfg.channel.snr_dB), ...
    "LinkSweepFrames", 1, ...
    "LinkSweepTrialsPerSNR", double(cfg.run.totalSlots), ...
    "LinkReferenceSweepFrames", double(cfg.run.totalSlots), ...
    "LinkSweepMaxPoints", 1, ...
    "LinkAdaptiveSweepEnabled", false, ...
    "LinkAdaptiveSweepStep_dB", 2, ...
    "LinkAdaptiveSweepMaxPoints", 1, ...
    "SaveFigures", false);
runFolder = fullfile(tmp, "air_interface");
caught = [];
out = struct("Ok", false);
logText = evalc('try, out = sixgr.truth.runWaveformLinkBundle(cfg, runFolder, opt); catch ME, caught = ME; end');
if ~isempty(caught)
    knownCoverageGuard = contains(string(caught.identifier), "PrimarySummarySkipped") || ...
        contains(string(caught.message), "Primary link KPI summary contains skipped rows");
    if ~knownCoverageGuard
        rethrow(caught);
    end
else
    assert(logical(sixgr.util.structGet(out, "Ok", false)), ...
        "Coupled truth live refresh throttle bundle should complete cleanly.");
end

chunkTokens = regexp(logText, ...
    '(?m)Executing coupled (DL|UL) chunk: sweep=\d+/\d+ slot=(\d+)/(\d+) chunk=\d+-\d+ of \d+\.', 'tokens');
refreshTokens = regexp(logText, ...
    '(?m)(DL|UL) heavy live artifact refresh: reason=post_grant_chunk slot=(\d+)/(\d+) interval=\d+\.', 'tokens');

assert(~isempty(chunkTokens), "Throttle regression must execute at least one coupled chunk.");
assert(~isempty(refreshTokens), "Throttle regression must emit at least one heavy refresh milestone.");

chunkKeys = localBuildDirectionSlotKeys(chunkTokens);
refreshKeys = localBuildDirectionSlotKeys(refreshTokens);

[uniqueChunkKeys, ~, chunkIdx] = unique(chunkKeys);
chunkCounts = accumarray(chunkIdx, 1);
assert(any(chunkCounts > 1), ...
    "Throttle regression must exercise multiple chunk publishes for at least one direction/slot.");

[uniqueRefreshKeys, ~, refreshIdx] = unique(refreshKeys);
refreshCounts = accumarray(refreshIdx, 1);
assert(all(refreshCounts == 1), ...
    "Heavy live artifact refresh must occur at most once per direction/slot milestone.");
assert(all(ismember(uniqueRefreshKeys, uniqueChunkKeys)), ...
    "Each heavy live refresh must correspond to a real executed direction/slot chunk sequence.");

ok = true;
end

function keys = localBuildDirectionSlotKeys(tokenList)
keys = strings(numel(tokenList), 1);
for i = 1:numel(tokenList)
    token = tokenList{i};
    keys(i) = string(token{1}) + "_" + string(token{2});
end
end
