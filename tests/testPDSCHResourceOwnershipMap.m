function ok = testPDSCHResourceOwnershipMap()
%TESTPDSCHRESOURCEOWNERSHIPMAP Verify exact ownership and resource planning.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
allocation = 0:167;
reservations = struct( ...
    "SSB", 0:11, ...
    "CORESET", 6:17, ...
    "NZPCSIRS", 12:23, ...
    "ZPCSIRS", zeros(1, 0), ...
    "LTECRS", zeros(1, 0), ...
    "RateMatchPattern", 18:29);
map = sixgr.pdsch.PDSCHResourceOwnershipMap( ...
    allocation, reservations);
assert(map.PairwiseOverlapMultiplicity == 18, ...
    "Reservation pairwise-overlap multiplicity must remain explicit.");
assert(isequal(map.ReservedUnionIndices(:).', 0:29) && ...
    isequal(map.DataIndices(:).', 30:167), ...
    "Ownership map did not resolve the exact reservation union.");
multi = map.Entries.ResolvedStatus == "reserved_multi_source";
assert(nnz(multi) == 18 && ...
    all(map.Entries.ReservationSourceCount(multi) >= 2), ...
    "Legal multi-source reservations lost their provenance.");
assert(all(map.Entries.CollisionCount == 0), ...
    "Resolved ownership must have one owner per RE.");

context = struct( ...
    "PRBSet", 0, "SymbolAllocation", [0 14], ...
    "GridNumPRB", 1, ...
    "GridSymbolsPerSlot",14,"BWPStartPRB",0,"AbsoluteSlot",0, ...
    "UnavailableIndices",zeros(1,0), ...
    "DMRSIndicesPerPort", {cell(1, 0)}, ...
    "PTRSIndicesPerPort", {cell(1, 0)}, ...
    "DMRSLogicalPortSet",zeros(1,0), ...
    "PTRSLogicalPortSet",zeros(1,0), ...
    "LayerCountPerCodeword", 1, ...
    "QmPerCodeword", 6, ...
    "CodeBlockCountPerCodeword", 2);
plan = sixgr.pdsch.PDSCHResourcePlan(map, context);
assert(plan.ExactDataRECount == 138 && ...
    plan.NREPerPRB == 138, ...
    "Resource plan changed the exact ownership-map data count.");
assert(plan.GPerCodeword == 828 && ...
    sum(plan.EPerCodeBlock{1}) == plan.GPerCodeword, ...
    "Resource plan did not derive exact G/E from data REs.");
assert(numel(plan.DataIndicesPerLayer) == 1 && ...
    isequal(plan.DataIndicesPerLayer{1}, plan.DataIndices), ...
    "Resource plan data-per-layer map is inconsistent.");
assert(height(plan.OwnershipMap.Entries) == 168 ...
    && all(plan.OwnershipMap.Entries.InsidePDSCHAllocation) ...
    && plan.OwnershipMap.ReferencesResolved, ...
    "Resolved ownership does not span the explicit carrier-slot universe.");

offsetContext = context;
offsetContext.BWPStartPRB = 24;
offsetContext.AbsoluteSlot = 71;
offsetPlan = sixgr.pdsch.PDSCHResourcePlan(map,offsetContext);
first = offsetPlan.OwnershipMap.Entries(1,:);
assert(first.GridPRB0Based == 0 ...
    && first.BWPRelativePRB0Based == 0 ...
    && first.CarrierPRB0Based == 24 ...
    && first.AbsoluteSlot == 71, ...
    "Nonzero carrier/BWP origin changed local grid-index semantics.");

partial = sixgr.pdsch.PDSCHResourceOwnershipMap(0:11,struct());
partialResolved = partial.resolve(struct( ...
    "UniverseIndices",0:167,"UnavailableIndices",zeros(1,0), ...
    "DMRSIndicesPerPort",{cell(1,0)}, ...
    "PTRSIndicesPerPort",{cell(1,0)}, ...
    "DMRSLogicalPortSet",zeros(1,0), ...
    "PTRSLogicalPortSet",zeros(1,0), ...
    "GridNumPRB",1,"GridSymbolsPerSlot",14, ...
    "BWPStartPRB",24,"AbsoluteSlot",71));
assert(nnz(partialResolved.Entries.ResolvedStatus ...
    == "outside_pdsch_allocation") == 156, ...
    "Carrier-slot ownership did not expose outside-allocation REs.");

unavailableContext = context;
unavailableContext.UnavailableIndices = 150:155;
unavailablePlan = sixgr.pdsch.PDSCHResourcePlan(map,unavailableContext);
unavailableRows = unavailablePlan.OwnershipMap.Entries. ...
    ResolvedStatus == "unavailable_by_frame_direction";
assert(nnz(unavailableRows) == 6 ...
    && unavailablePlan.ExactDataRECount == 132, ...
    "Frame-direction-unavailable REs were not represented and excluded.");

localAssertError(@() sixgr.pdsch.PDSCHResourceOwnershipMap( ...
    0:11, struct("SSB", 12)), ...
    "sixgr:pdsch:ReservedREOutsideAllocation");
localAssertError(@() sixgr.pdsch.PDSCHResourceOwnershipMap( ...
    0:11, struct("SSB", 0:11)), ...
    "sixgr:pdsch:NoPDSCHDataREAfterReservation");
incompleteMap = sixgr.pdsch.PDSCHResourceOwnershipMap( ...
    0:166, struct());
localAssertError(@() sixgr.pdsch.PDSCHResourcePlan( ...
    incompleteMap, context), ...
    "sixgr:pdsch:IncompleteScheduledResourceOwnership");
localAssertError(@() sixgr.pdsch.PDSCHResourcePlan(map, ...
    localCollisionContext()), ...
    "sixgr:pdsch:DataDMRSPTRSReservedCollision");
ok = true;
end

function context = localCollisionContext()
context = struct( ...
    "PRBSet", 0, "SymbolAllocation", [0 14], ...
    "GridNumPRB", 1, ...
    "GridSymbolsPerSlot",14,"BWPStartPRB",0,"AbsoluteSlot",0, ...
    "UnavailableIndices",zeros(1,0), ...
    "DMRSIndicesPerPort", {{0}}, ...
    "PTRSIndicesPerPort", {cell(1, 0)}, ...
    "DMRSLogicalPortSet",7, ...
    "PTRSLogicalPortSet",zeros(1,0), ...
    "LayerCountPerCodeword", 1, ...
    "QmPerCodeword", 2, ...
    "CodeBlockCountPerCodeword", 1);
end

function localAssertError(fn, expectedID)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(expectedID), ...
        "Observed %s, expected %s.", ME.identifier, expectedID);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.", expectedID);
end
