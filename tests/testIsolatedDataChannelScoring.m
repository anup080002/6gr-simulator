function ok=testIsolatedDataChannelScoring()
% Actual DL/UL reception, independent pilot scoring and persisted energies.
setup6GRSimToolkit('Verbose',false);
previousRNG=rng; restoreRNG=onCleanup(@()rng(previousRNG)); %#ok<NASGU>
% A single receive branch must use the same column resource axis as MIMO.
context=struct('Channel',"PDSCH",'Slot',0,'UEIndex',1,'ConfiguredSNR_dB',20, ...
    'ChannelEstimateSource',"test_estimate",'ChannelReferenceSource',"test_reference", ...
    'ChannelReferencePlane',"test_grid");
for branches=[1 2 4]
    reference=complex(ones(12,2,branches)); estimate=reference+0.1i;
    [rows,score]=sixgr.report.buildReceiverChannelEstimateTable(estimate,reference,[1;4;17],context);
    assert(height(rows)==3*branches && abs(score.Linear-.01)<1e-12 && ...
        isequal(rows.RxBranchIndex0,reshape(repelem(0:branches-1,3),[],1)));
end
cfg=withCanonicalSchedulerTiming(sixgr.config.defaultConfig());
cfg.run.shortRun=true;
cfg.run.noiseOperatingMode="standalone_awgn_snr_argument";
cfg.phy.csirs.enable=false; cfg.phy.csirs.enabled=false;
cfg.lls6g.userContext.UEIndex=2;
cfg.phy.pdsch.RNTI=181; cfg.phy.pusch.RNTI=182;
cfg.outputs.saveFigures=false;
folder=fullfile(pwd,'results','lls','isolated_channel_scoring', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(folder); cfg.run.rootRunFolder=folder;
save(fullfile(folder,'configuration.mat'),'cfg');
fprintf('ISOLATED_CHANNEL_SCORING_EVIDENCE=%s\n',folder);
for direction=["DL","UL"]
    cfg.outputs.phySignalDiagnosticEnabled=false;
    rng(619034,'twister');
    baseline=runOne(cfg,direction);
    cfg.outputs.phySignalDiagnosticEnabled=true;
    rng(619034,'twister');
    measured=runOne(cfg,direction);
    T=measured.TrialTable; B=baseline.TrialTable;
    writetable(T,fullfile(folder,lower(direction)+'_scored.csv'));
    writetable(B,fullfile(folder,lower(direction)+'_baseline.csv'));
    assert(height(T)==1 && ~T.Crash && ~B.Crash && isfinite(T.NMSE_dB), ...
        'test:MissingIndependentChannelScore','Actual %s scoring must execute without a PHY or publication crash.',direction);
    for name=["CRCPass","BitErrors","BitsCompared","TBSize_bits","GoodBits", ...
            "HARQCurrentDecodeOK","HARQCombinedDecodeOK"]
        assert(isequaln(T.(name),B.(name)), ...
            'test:ScoringChangedReception','Post-decode scoring must not change %s %s.',direction,name);
    end
    assert(~T.ChannelEstimateReferenceUsedByReceiver && ...
        contains(T.NMSESource,'same_executed_desired_link_waveform_post_decode'), ...
        'test:ScoringOracle','Retain the independently executed scoring plane.');
    resources=sixgr.util.csvReadTable(fullfile(folder,T.ChannelEstimateResourcesCSV));
    value=10*log10(sum(resources.ChannelErrorEnergy)/sum(resources.ReferenceChannelEnergy));
    assert(abs(value-T.NMSE_dB)<1e-10 && height(resources)==T.ChannelEstimateComparedValues, ...
        'test:ScoringEnergyClosure','Saved complex pilot errors must reproduce %s NMSE.',direction);
    assert(string(sixgr.phy.waveform.WaveformHash.file(fullfile(folder,T.ChannelEstimateResourcesCSV)))== ...
        string(T.ChannelEstimateResourcesCSVSHA256));
    assert(isfile(fullfile(folder,T.ChannelEstimateMATFile)));
    live=sixgr.truth.exportLLSLiveSignalChainTables( ...
        fullfile(folder,lower(direction)+'_live'),T,measured.ConstellationSamples, ...
        struct('WaveformPreviewTable',measured.WaveformPreviewTable,'FinalSnapshot',true));
    wave=measured.WaveformPreviewTable;
    assert(~isempty(wave) && all(wave.Direction==direction) && all(wave.SNR_dB==20), ...
        'test:MissingMeasuredWaveform','Actual receiver preview must retain direction and SNR.');
    assert(all(ismember(["UEIndex","RNTI","BaseStationID"], ...
        string(wave.Properties.VariableNames))) && ...
        all(wave.UEIndex==T.UEIndex) && all(wave.RNTI==T.RNTI), ...
        'test:WaveformUEIdentityLost','Preview must carry the same executed UE identity as its receiver trial.');
    savedWave=sixgr.util.csvReadTable(live.WaveformPreviewPath,'TextType','string');
    for name=["TxReal","TxImag","RxReal","RxImag","SampleIndex","Time_s", ...
            "TxAntennaIndex","RxAntennaIndex","UEIndex","RNTI","BaseStationID"]
        assert(isequaln(savedWave.(name),wave.(name)), ...
            'test:WaveformPreviewChanged','Final CSV must retain exact measured %s samples.',name);
    end
    exported=sixgr.util.csvReadTable(live.ChannelEstimationTracePath,'TextType','string');
    assert(height(exported)==1 && exported.NMSE_dB==T.NMSE_dB && ...
        string(exported.NMSESource)==string(T.NMSESource) && ...
        string(exported.ChannelEstimateResourcesCSV)==string(T.ChannelEstimateResourcesCSV) && ...
        string(exported.NMSEDefinition)=="10log10(sum_abs_Hest_minus_Href_squared_over_sum_abs_Href_squared)", ...
        'test:NMSELiveSemantics','Live channel NMSE must retain the independent scorer and reference identity.');
    assert(exported.PilotReconstructionResidualRatio_dB==T.PilotReconstructionResidualRatio_dB, ...
        'test:PilotResidualIdentity','Keep the distinct measured pilot residual alongside channel NMSE.');
    % Follow the real receiver row through the production MIMO exporter too.
    % This checks measurement lineage, not complete scenario qualification.
    raw=struct(); raw.(direction)=T;
    mimoFolder=fullfile(folder,lower(direction)+'_mimo');
    sixgr.mimo.exportMIMOEvidenceArtifacts(mimoFolder,cfg,raw, ...
        'RunId',"isolated_channel_scoring",'StrictMode',true);
    layers=sixgr.util.csvReadTable(fullfile(mimoFolder,'beamforming','csv', ...
        'mimo_layer_metrics.csv'),'TextType','string');
    assert(all(layers.TrialChannelEstimateNMSEdB==T.NMSE_dB) && ...
        all(string(layers.TrialChannelEstimateNMSESource)==string(T.NMSESource)) && ...
        all(string(layers.ChannelEstimateNMSEStatus)=="unavailable_trial_aggregate_only") && ...
        all(isnan(layers.ChannelEstimateNMSEdB)), ...
        'test:NMSEMIMOExport','Real receiver NMSE must retain trial scope and its reference source.');
    assert(all(layers.UEId==2), ...
        'test:NMSEMIMOUEIdentity','The MIMO export must retain the executed UE binding.');
    unavailable=sixgr.truth.exportLLSLiveSignalChainTables( ...
        fullfile(folder,lower(direction)+'_unscored_live'),B,table(),struct());
    unavailableT=sixgr.util.csvReadTable(unavailable.ChannelEstimationTracePath,'TextType','string');
    assert(isnan(unavailableT.NMSE_dB) && ...
        string(unavailableT.NMSEInterpretation)=="unavailable_independent_channel_reference", ...
        'test:UnknownNMSELiveSemantics','A measured pilot residual must not become channel NMSE.');
    fprintf('%s NMSE_dB=%.9g scored_values=%d CRC=%d\n', ...
        direction,T.NMSE_dB,T.ChannelEstimateComparedValues,T.CRCPass);
end
% Unknown rows remain unknown when other rows contain measurements.
T=table(nan(2,1),'VariableNames',{'NMSE_dB'});
T=sixgr.link.bindDataChannelScoreRows(T,{[];struct('NMSE_dB',-20,'NMSESource',"observed")});
assert(isnan(T.NMSE_dB(1)) && T.NMSESource(1)=="" && T.NMSE_dB(2)==-20);
ok=true;
end

function result=runOne(cfg,direction)
if direction=="DL"
    result=sixgr.link.runDLPDSCHThroughput(cfg,'NumFrames',1,'SNR_dB',20, ...
        'ExecutionProfile','phy_calibration');
else
    result=sixgr.link.runULPUSCHThroughput(cfg,'NumFrames',1,'SNR_dB',20);
end
end
