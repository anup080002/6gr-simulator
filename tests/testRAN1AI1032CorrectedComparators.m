function ok=testRAN1AI1032CorrectedComparators()
%TESTRAN1AI1032CORRECTEDCOMPARATORS Exact installed C0/C1/C2a/C3/C4/C5 maps.
setup6GRSimToolkit('Verbose',false);
[c0,n0]=sixgr.studies.ran1ai1032.MCSCatalog.correctedComparator('C0');
[c1,n1]=sixgr.studies.ran1ai1032.MCSCatalog.correctedComparator('C1');
[c2,n2]=sixgr.studies.ran1ai1032.MCSCatalog.correctedComparator('C2a');
[c3,n3]=sixgr.studies.ran1ai1032.MCSCatalog.correctedComparator('C3');
[c4,n4]=sixgr.studies.ran1ai1032.MCSCatalog.correctedComparator('C4');
[c5,n5]=sixgr.studies.ran1ai1032.MCSCatalog.correctedComparator('C5');
assert(isequal(c0.entry_id(1:28),"B"+compose('%02d',(0:27)')) && ...
    isequal(c0.entry_id(29:32),["R_QPSK";"R_16QAM";"R_64QAM";"R_256QAM"]));
expectedC1=["B00";"B01";"B03";"B05";"B07";"B09"; ...
    "B"+compose('%02d',(11:27)');"H0";"H1";"H2";"H3"];
assert(isequal(c1.entry_id(1:27),expectedC1) && ...
    isequal(c1.entry_id(28:32), ...
        ["R_QPSK";"R_16QAM";"R_64QAM";"R_256QAM";"R_1024QAM"]));
assert(isequal(c2.entry_id,["B"+compose('%02d',(0:27)'); ...
    "H0";"H1";"H2";"H3"]) && all(c2.entry_kind=="regular"));
assert(isequal(c4.entry_id,c1.entry_id) && ...
    isequal(c4.indication_index,c1.indication_index) && ...
    all(c4.indication_width_bits==6) && all(c1.indication_width_bits==5));
assert(isequal(c3.entry_id(c3.indication_index==32),"H0") && ...
    isequal(c3.entry_id(c3.indication_index==36),"R_1024QAM"));
assert(isequal(c5.entry_id(c5.indication_index==55),"B27") && ...
    isequal(c5.entry_id(c5.indication_index==64),"H0") && ...
    isequal(c5.entry_id(c5.indication_index==79),"R_1024QAM"));
maps={c0,c1,c2,c3,c4,c5}; names=[n0,n1,n2,n3,n4,n5];
for m=1:numel(maps)
    map=maps{m}; definition=sixgr.phy.research.resolveExperimentalMCSTable(names(m));
    assert(height(map)==size(definition.Rows,1)+size(definition.ReservedRows,1));
    for index=0:2^definition.IndexWidthBits-1
        row=map(map.indication_index==index,:);
        profile=sixgr.link.resolveMCSProfile(names(m),index);
        if isempty(row) || row.entry_kind=="stored_tbs"
            assert(~profile.Valid, ...
                'Unassigned/stored-TBS codepoint cannot start a new TB.');
        else
            assert(profile.Valid && profile.Qm==row.Qm && ...
                abs(profile.TargetCodeRate-row.target_code_rate_x1024/1024)<1e-14, ...
                'Installed comparator changed an exact physical pair.');
        end
    end
end
direct=sixgr.phy.research.resolveExperimentalMCSTable(n5);
assert(direct.IndexWidthBits==7 && direct.DirectQmFieldBits==3 && ...
    direct.DirectSelectorBits==4 && ...
    all(floor(direct.Rows(:,1)/16)==(direct.Rows(:,2)-2)/2) && ...
    all(mod(direct.ReservedRows(:,1),16)==15), ...
    'C5 must be an explicit 3+4 on-air indication, not a relabelled flat table.');
scenario=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_four_port_connected_research_ul_fixture.yaml');
base=sixgr.lls6g.buildInternalConfig(scenario,tempname);
widths=zeros(3,1);
for k=1:3
    name=[n1,n4,n5]; cfg=base;
    cfg.phy.pusch.mcsTable=char(name(k));
    cfg.phy.pusch.experimentalMCSTable= ...
        sixgr.phy.research.resolveExperimentalMCSTable(name(k));
    context=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,'0_1');
    schema=sixgr.phy.pdcch.DCISchemaEngine.resolve(context);
    widths(k)=schema.RawBits;
    assert(schema.Definitions([schema.Definitions.Name]=="mcs").Width==4+k, ...
        'C1/C4/C5 must use exactly 5/6/7 on-air MCS bits.');
end
assert(isequal(diff(widths),[1;1]), ...
    'Only one raw DCI MCS bit may change between C1/C4/C5.');
ok=true;
fprintf('RAN1_AI1032_CORRECTED_COMPARATORS_PASS C0=%d C1=%d C2a=%d C3=%d C4=%d C5=%d\n', ...
    height(c0),height(c1),height(c2),height(c3),height(c4),height(c5));
end
