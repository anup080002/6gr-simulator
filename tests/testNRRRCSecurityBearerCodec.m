function ok=testNRRRCSecurityBearerCodec()
% Codec-process boundary only: no authenticated SRB delivery or activation.
for transaction=0:3
    semantic=struct('transaction_id',transaction,'ciphering_algorithm',"nea0",'integrity_algorithm',"nia2");
    tx=sixgr.rrc.asn1.NRAccessMessageCodec.encode('security_mode_command',semantic);
    rx=sixgr.rrc.asn1.NRAccessMessageCodec.decode('security_mode_command',tx.Bytes);
    assert(isequaln(rx.Semantic,tx.Semantic)&&isequal(rx.Bytes,tx.Bytes)&& ...
        rx.Semantic.integrity_algorithm=="nia2"&&~rx.SecurityActivated&&~rx.PhysicalReceptionProved);
    for kind=["security_mode_complete","security_mode_failure","reconfiguration_complete"]
        tx=sixgr.rrc.asn1.NRAccessMessageCodec.encode(kind,struct('transaction_id',transaction));
        rx=sixgr.rrc.asn1.NRAccessMessageCodec.decode(kind,tx.Bytes);
        assert(rx.Semantic.transaction_id==transaction&&isequal(rx.Bytes,tx.Bytes));
    end
end
s=struct('transaction_id',2,'cell_group_id',0,'drb_id',1,'lcid',4, ...
    'pdcp',struct('sn_size_ul',"len12bits",'sn_size_dl',"len18bits", ...
        'discard_timer',"ms100",'t_reordering',"ms40",'integrity_protection',false), ...
    'sdap',struct('pdu_session',1,'qfi',9,'header_ul',"present",'header_dl',"present",'default_drb',true), ...
    'rlc_am',struct('sn_size_ul',"size12",'sn_size_dl',"size18",'t_poll_retransmit',"ms45", ...
        'poll_pdu',"p16",'poll_byte',"kB25",'max_retx_threshold',"t8", ...
        't_reassembly',"ms35",'t_status_prohibit',"ms10"), ...
    'logical_channel',struct('priority',3,'prioritised_bit_rate',"kBps8", ...
        'bucket_size_duration',"ms100",'logical_channel_group',1,'scheduling_request_id',0, ...
        'logical_channel_sr_mask',false,'logical_channel_sr_delay_timer_applied',false));
tx=sixgr.rrc.asn1.NRAccessMessageCodec.encode('reconfiguration',s);
rx=sixgr.rrc.asn1.NRAccessMessageCodec.decode('reconfiguration',tx.Bytes);
assert(isequaln(rx.Semantic,tx.Semantic)&&isequal(tx.Bytes,rx.Bytes));
n=rx.NestedConfiguration;
assert(n.new_drb_setup_only&&~n.drb_integrity_protection_field_present&& ...
    n.required_pdcp_optional_fields_present&& ...
    string(n.mcg_location)=="rrcReconfiguration.nonCriticalExtension.masterCellGroup"&& ...
    ~rx.DedicatedDRBConfigured&&~rx.SecurityActivated&&~rx.NASValidated);
wire=uint8(sscanf(n.master_cell_group_uper_hex,'%2x')).';
assert(string(sixgr.rrc.asn1.asn1SHA256Hex(wire))==string(n.master_cell_group_sha256));
ok=true;
end
