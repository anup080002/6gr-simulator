cfg = localCfg("nonCodebook", false, 1, 1, NaN);
cfg.phy.pusch.equalizer = "IRC";
cfg.phy.pusch.singleUserEqualizer = "MMSE";
cfg.phy.pusch.muMIMOEqualizer = "IRC";
[tx, ~] = sixgr.phy.ul.PUSCH_Tx(cfg, "CompactOutput", false);
[rx, ~] = sixgr.phy.ul.PUSCH_Rx(tx.Waveform, cfg, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "PUSCHIndices", tx.PUSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", 1e-9, ...
    "NoiseVarDomain", "grid", ...
    "CodingLayout", tx.CodingLayout, ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true);
assert(logical(rx.Ok), ...
    "A single-user PUSCH must decode with its YAML-owned MMSE receiver.");
assert(string(rx.EqualizerRequestedType) == "MMSE" && ...
    string(rx.EqualizerType) == "MMSE", ...
    ["The single-user PUSCH receiver must not request strict IRC merely " ...
     "because the same scenario reserves IRC for MU-MIMO grants."]);
end

function artifact=localAssertNoNoiseCase(cfg, label, artifactRoot)
if nargin<3, artifactRoot=""; end
artifact=struct('Status',"not_requested",'ArtifactRoot',"");
% Earlier CP cases have consumed randomness. Retain the actual state here,
% never relabel this observation with the test's initial seed alone.
rngBeforeTX=rng;
[tx, ~] = sixgr.phy.ul.PUSCH_Tx(cfg, "CompactOutput", false);
[rx, ~] = sixgr.phy.ul.PUSCH_Rx(tx.Waveform, cfg, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "PUSCHIndices", tx.PUSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", 1e-9, ...
    "NoiseVarDomain", "grid", ...
    "CodingLayout", tx.CodingLayout, ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true);

assert(logical(rx.Ok) && ~logical(rx.CRCError), "%s no-noise PUSCH must pass CRC.", label);
ber = sum(int8(tx.TransportBlock(:)) ~= int8(rx.TransportBlock(:))) / numel(tx.TransportBlock);
assert(ber == 0, "%s no-noise PUSCH must have BER=0.", label);

[metrics, samples] = sixgr.link.deriveModulationTrackingMetrics(tx, rx, cfg, "UL");
assert(height(samples) == double(tx.QAMSymbolCount) && ...
    all(samples.CaptureScope == "full_allocation_paired_symbols"), ...
    "%s must retain every executed receiver QAM symbol, not a preview.", label);
localAssertCoordinateDomain(tx,rx,cfg,samples,label);
assert(double(metrics.SymbolErrorRate) == 0 && double(metrics.SymbolErrors) == 0, ...
    "%s no-noise PUSCH must have layer-domain SER=0.", label);
assert(strcmpi(string(metrics.SymbolComparisonDomain), "layer"), ...
    "%s SER/EVM must compare layer-domain symbols.", label);
assert(double(metrics.DemapperLLRCount) == double(metrics.RateMatchedBitCount), ...
    "%s demapper LLR count must equal the UL-SCH G contract.", label);

directLLR = nrPUSCHDecode(rx.Carrier, rx.PUSCH, rx.DecoderInputSymbolsForEvidence, rx.PreEqualizationNoiseVar);
directLLR = localNormalizeLLR(directLLR);
[directLLR, expectedCSIInfo] = sixgr.phy.rx.applyCSIToCodewordLLR( ...
    directLLR, rx.EqualizerCSIForEvidence, rx.PUSCH.Modulation, ...
    "PostEqSINR_dB", rx.PostEqSINR_dB, "CodewordIndex", 1);
gotLLR = double(rx.CodewordLLR(:));
tol = 1e-10 * max(1, max(abs(directLLR), [], "omitnan"));
assert(numel(gotLLR) == numel(directLLR), ...
    "%s receiver LLR count must match direct nrPUSCHDecode.", label);
assert(max(abs(gotLLR - directLLR), [], "omitnan") <= tol, ...
    "%s receiver LLRs must equal nrPUSCHDecode followed by one MMSE CSI weighting operation.", label);
assert(logical(expectedCSIInfo.Applied) && logical(rx.LLRCSIWeightApplied), ...
    "%s PUSCH RX must apply MMSE equalizer CSI once after demapping.", label);
assert(string(rx.LLRScalingConvention) == "pre_equalization_noise_plus_mmse_equalizer_csi", ...
    "%s PUSCH RX must declare the standard pre-eq-noise plus CSI convention.", label);
assert(logical(rx.LLRDoubleWeightingGuard), ...
    "%s PUSCH RX must expose the double-weighting guard.", label);

lineage = rx.DecodedBitLineage;
assert(double(lineage.ULSCHDemapperLLRCount) == double(tx.DataRateMatchedBitCount), ...
    "%s decoded lineage must preserve UL-SCH demapper G.", label);
assert(double(lineage.RateRecoveredRows) == double(tx.CodingLayout.MotherCodeLength) && ...
        double(lineage.RateRecoveredCodeBlocks) == double(tx.CodingLayout.NumCodeBlocks), ...
    "%s decoded lineage must preserve rate-recovery mother-code dimensions.", label);
if strlength(artifactRoot)>0
    artifact=localRetainNativeDFT(artifactRoot,label,cfg,tx,rx,metrics,samples,rngBeforeTX);
end
end

