function cfg = localCfg(scheme, transformPrecoding, nLayers, nPorts, tpmi)
cfg = sixgr.config.defaultConfig();
cfg.outputs.constellationCaptureScope = "full_allocation";
cfg.run.shortRun = true;
cfg.run.strictNoiseVarianceRequired = false;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.snr_dB = 45;
cfg.phy.nTxAnt = nPorts;
cfg.phy.nRxAnt = nPorts;
cfg.channel.nTxAnt = nPorts;
cfg.channel.nRxAnt = nPorts;
cfg.scenario.ue.nTxAnt = nPorts;
cfg.antenna.ue.numElements = nPorts;
cfg.phy.carrier.NSizeGrid = 12;
cfg.phy.carrier.SubcarrierSpacing = 30;
cfg.phy.pusch.prbSet = 0:5;
cfg.phy.pusch.symbolAllocation = [0 10];
cfg.phy.pusch.modulation = "QPSK";
cfg.phy.pusch.codeRate = 0.30;
cfg.phy.pusch.mcsIndex = 4;
cfg.phy.pusch.numLayers = nLayers;
cfg.phy.pusch.nLayers = nLayers;
cfg.phy.pusch.numAntennaPorts = nPorts;
cfg.phy.pusch.numPorts = nPorts;
% The strict production path must receive an explicit logical DM-RS port
% pool for every scheduled layer; a rank-one default is not expandable.
cfg.phy.pusch.dmrs.portSet = 0:(nLayers - 1);
cfg.phy.pusch.dmrs.DMRSPortSet = 0:(nLayers - 1);
cfg.phy.pusch.transmissionScheme = char(string(scheme));
cfg.phy.pusch.transformPrecoding = logical(transformPrecoding);
cfg.phy.pusch.enablePTRS = false;
cfg.phy.pusch.equalizer = "MMSE";
cfg.phy.pusch.measurements.decoderNoiseVarianceMode = "pre_equalization";
cfg.phy.channelEstimation.method = "LS";
if isfinite(double(tpmi))
    cfg.phy.pusch.TPMI = double(tpmi);
    cfg.phy.pusch.PMI = double(tpmi);
end
end

function llr = localNormalizeLLR(raw)
if iscell(raw)
    raw = raw{1};
end
llr = double(raw(:));
end

function tf = localHaveRequired5G()
tf = exist("nrPUSCH", "file") == 2 && ...
    exist("nrPUSCHDecode", "file") == 2 && ...
    exist("nrULSCHDemultiplex", "file") == 2 && ...
    exist("nrUCIDecode", "file") == 2 && ...
    exist("nrChannelEstimate", "file") == 2 && ...
    exist("nrRateRecoverLDPC", "file") == 2 && ...
    exist("nrLDPCDecode", "file") == 2;
end
