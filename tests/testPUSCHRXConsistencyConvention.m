    "HARQACK", int8(1), ...
    "CSIPart1", int8([1; 0; 1; 1; 0]), ...
    "CSIPart2", int8([0; 1; 1; 0; 1; 0]));
[tx, ~] = sixgr.phy.ul.PUSCH_Tx(cfg, ...
    "UCIPayload", uciPayload, ...
    "CompactOutput", false);
[rx, ~] = sixgr.phy.ul.PUSCH_Rx(tx.Waveform, cfg, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "PUSCHIndices", tx.PUSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", 1e-9, ...
    "NoiseVarDomain", "grid", ...
    "CodingLayout", tx.CodingLayout, ...
    "ExpectedUCIPayload", uciPayload, ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true);

assert(logical(rx.Ok) && logical(rx.HARQACKContentMatch) && ...
    logical(rx.CSI1ContentMatch) && logical(rx.CSI2ContentMatch), ...
