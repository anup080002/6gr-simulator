function localAssertUCIOnPUSCHAccounting()
cfg = localCfg("nonCodebook", false, 1, 1, NaN);
ackBits = int8([1; 0]);
uciPayload = sixgr.phy.ul.pusch.PUSCHUCIPayload( ...
    "HARQACK", ackBits);
[tx, ~] = sixgr.phy.ul.PUSCH_Tx(cfg, ...
    "UCIPayload", uciPayload, ...
    "CompactOutput", false);
[rx, ~] = sixgr.phy.ul.PUSCH_Rx(tx.Waveform, cfg, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "PUSCHIndices", tx.PUSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "NoiseVar", 1e-9, ...
    "NoiseVarDomain", "grid", ...
    "CodingLayout", tx.CodingLayout, ...
    "ExpectedUCIPayload", uciPayload, ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true);

assert(logical(rx.Ok), "UCI-on-PUSCH no-noise UL-SCH must pass CRC.");
assert(logical(rx.UCIOnPUSCHApplied) && logical(rx.HARQACKContentMatch), ...
    "Expected HARQ-ACK on PUSCH must be demultiplexed and decoded.");
assert(string(rx.HARQACKDecodeStatus) == "decoded_match", ...
    "Matching HARQ-ACK bits must carry the HARQ-specific decoded_match status.");
assert(double(rx.ULSCHDemapperLLRCount) == double(tx.DataRateMatchedBitCount), ...
    "UCI-on-PUSCH UL-SCH demapper LLR count must equal data G, not multiplexed total G.");
assert(double(rx.DemapperLLRCount) == double(tx.RateMatchedBitCount), ...
    "Total PUSCH demapper LLR count must preserve the multiplexed PUSCH G.");
assert(double(rx.RateRecoverInfo.InputLLRCount) == double(tx.DataRateMatchedBitCount), ...
    "Rate recovery must consume only UL-SCH LLRs after UCI demultiplexing.");

[metrics, ~] = sixgr.link.deriveModulationTrackingMetrics(tx, rx, cfg, "UL");
assert(double(metrics.RateMatchedBitCount) == double(tx.DataRateMatchedBitCount), ...
    "UCI-on-PUSCH modulation metrics must report UL-SCH data G for LDPC accounting.");
assert(double(metrics.DemapperLLRCount) == double(tx.DataRateMatchedBitCount), ...
    "UCI-on-PUSCH modulation metrics must report UL-SCH demapper LLR count.");
end

