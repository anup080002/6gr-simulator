function ok = testFrozenGrantWaveformReplayAuthority()
%TESTFROZENGRANTWAVEFORMREPLAYAUTHORITY Replay exact per-grant precoders.

setup6GRSimToolkit("Verbose", false);

cfg = sixgr.config.defaultConfig();
cfg.run.strictMode = true;
cfg.frequency.bandwidth_hz = 20e6;
cfg.channel.bandwidth_Hz = 20e6;
cfg.phy.channelBandwidth_MHz = 20;
cfg.channel.subcarrierSpacing_kHz = 30;
cfg.phy.carrier.SubcarrierSpacing = 30;
cfg.phy.carrier.NSizeGrid = 51;
cfg.channel.awgnOnly = true;
cfg.channel.model = "AWGN";
cfg.channel.fading.enable = false;
cfg.scenario.bs.nTxAnt = 2;
cfg.scenario.ue.nRxAnt = 2;
cfg.antenna.bs.numElements = 2;
cfg.antenna.bs.numRFChains = 2;
cfg.antenna.ue.numElements = 2;
cfg.antenna.ue.numRFChains = 2;
cfg.rf.bs.numRFChains = 2;
cfg.rf.ue.numRFChains = 2;
cfg.channel.nTxAnt = 2;
cfg.channel.nRxAnt = 2;
cfg.phy.nTxAnt = 2;
cfg.phy.nRxAnt = 2;
cfg.phy.beamManagement.hybridBeamformingEnabled = true;
cfg.phy.pdsch.numLayers = 2;
cfg.phy.pdsch.nLayers = 2;
cfg.phy.pdsch.numPorts = 2;
cfg.phy.pdsch.nPorts = 2;
cfg.phy.pdsch.modulation = "QPSK";
cfg.phy.pdsch.codeRate = 0.3;
cfg.phy.pdsch.symbolAllocation = [2 10];
cfg.phy.pdsch.dmrs.portSet = [0 1];
cfg.phy.csirs.enable = false;
cfg.phy.ptrs.enable = false;
cfg = sixgr.config.normalizeConfig(cfg);
sixgr.config.validateConfig(cfg);

arch = sixgr.rf.AntennaArrayFactory.resolvePortArchitecture(cfg, "bs", ...
    "Signal", "PDSCH", "MinimumPorts", 2);
logicalMatrices = cat(3, eye(2) ./ sqrt(2), [1 1; 1 -1] ./ 2);
replay = cell(2, 1);
expectedDigest = strings(2, 1);

for index = 1:2
    logicalMatrix = logicalMatrices(:, :, index);
    physicalMatrix = double(arch.HybridElementToPortMatrix) * logicalMatrix;
    grant = struct( ...
        "Direction", "DL", "Frame", 0, "Slot", 0, ...
        "RNTI", 100 + index, "UEIndex", index, "ServingCell", 1, ...
        "PRBSet", 0:5, "SymbolAllocation", [2 10], ...
        "Modulation", "QPSK", "NumLayers", 2, "Layers", 2, ...
        "NumLogicalPorts", 2, "NumRFChains", 2, ...
        "TargetCodeRate", 0.3, "MCSIndex", 1, ...
        "PrecodingMatrixLogicalPorts", logicalMatrix, ...
        "PrecodingMatrix", physicalMatrix, ...
        "HybridElementToPortMatrix", double(arch.HybridElementToPortMatrix), ...
        "PrecoderNormalizationConvention", "unit_frobenius", ...
        "PrecoderSource", "focused_frozen_grant_regression");
    grant.PHYGrant = sixgr.phy.grant.freezePHYGrant(cfg, "DL", grant, ...
        "SNR_dB", 45, "Frame", 0, "Slot", 0);
    expectedDigest(index) = string( ...
        grant.PHYGrant.PrecodingState.SelectedMatrixSHA256);
    replay{index} = sixgr.system.waveform.replayGrant( ...
        cfg, "DL", grant, [], 45, "StrictMode", true, ...
        "CompactPHYIO", true, "FastAWGNPath", false, ...
        "NoiseSeed", 8800+index, "ChannelSeed", 9900+index);
end

requestedDigest = string(cellfun(@(x)x.RequestedPrecoderSHA256, replay, ...
    "UniformOutput", false));
appliedDigest = string(cellfun(@(x)x.AppliedPrecoderSHA256, replay, ...
    "UniformOutput", false));
assert(all(requestedDigest == expectedDigest), ...
    "Every replay must request the exact physical precoder frozen into its grant.");
assert(all(appliedDigest == expectedDigest), ...
    "Every waveform must apply the exact frozen physical precoder.");
assert(expectedDigest(1) ~= expectedDigest(2), ...
    "The regression grants must carry distinct physical precoder identities.");
assert(strlength(string(replay{1}.FrozenGrantContextId)) > 0 && ...
    strlength(string(replay{2}.FrozenGrantContextId)) > 0, ...
    "Every replay must disclose its frozen configuration-authority context identity.");
assert(all(cellfun(@(x)logical(x.WaveformReplayExecuted), replay)), ...
    "Both frozen grants must execute through the waveform chain.");
for index = 1:numel(replay)
    r = replay{index};
    assert(r.AWGNReferencePlane == "occupied_resource_grid_re_pre_equalization" && ...
        r.AWGNNoiseSource == "sixgr.phy.waveform.addOccupiedREAWGN" && ...
        isfinite(r.AWGNSignalEnergyPerOccupiedRE) && ...
        abs(r.AWGNGridNoiseVariance - ...
            r.AWGNSignalEnergyPerOccupiedRE*10^(-45/10)) < 1e-12 && ...
        abs(r.AWGNSampleNoiseVariance*r.AWGNSampleToGridNoiseGain - ...
            r.AWGNGridNoiseVariance) < 1e-12, ...
        "Frozen-grant replay must use the executed occupied-RE Es/N0 plane.");
    assert(r.AWGNNoiseSeedApplied && r.AWGNNoiseSeed == 8800+index && ...
        r.ReplayChannelSeed == 9900+index && ...
        ~r.ReplayChannelSeedApplied && ...
        isfinite(r.ReplaySampleRateHz) && r.ReplaySampleRateHz > 0, ...
        "AWGN replay must retain its noise seed without claiming fading-channel use.");
    assert(r.TransmittedTransportBlockBits == r.TransportBlockSize && ...
        r.TransmittedRNTI == 100+index && ...
        isequal(r.TransmittedPRBSet, 0:5) && ...
        isequal(r.TransmittedSymbolAllocation, [2 10]) && ...
        r.TransmittedNumLayers == 2 && ...
        isequal(r.TransmittedModulation, "QPSK") && ...
        isequal(r.TransmittedTransportBlockSizes, r.TransportBlockSize) && ...
        r.TransmittedTransportBlockSHA256 == string(sixgr.util.sha256Hex( ...
            uint8(zeros(r.TransmittedTransportBlockBits,1)))) && ...
        r.TransmittedRV == 0, ...
        "Waveform replay must retain the actual transmitted TB and RV identity.");
end

explicitBits = int8(mod((1:replay{2}.TransportBlockSize).',2));
explicitReplay = sixgr.system.waveform.replayGrant( ...
    cfg, "DL", grant, explicitBits, 45, "StrictMode", true, ...
    "CompactPHYIO", true, "FastAWGNPath", false, ...
    "NoiseSeed", 8810, "ChannelSeed", 9910);
assert(explicitReplay.WaveformReplayExecuted && ...
    explicitReplay.TransmittedRNTI == grant.RNTI && ...
    explicitReplay.TransmittedTransportBlockBits == numel(explicitBits) && ...
    explicitReplay.TransmittedTransportBlockSHA256 == ...
        string(sixgr.util.sha256Hex(uint8(explicitBits))), ...
    "An explicit TB must retain its own physical transmitter hash.");

% Two otherwise identical scheduled grants must not share an RNTI=1
% payloadless waveform template.  The UE-specific scrambling identity is
% part of the physical grant, not a cache-normalization hint.
grant.RNTI = 103;
grant.PHYGrant = sixgr.phy.grant.freezePHYGrant(cfg, "DL", grant, ...
    "SNR_dB", 45, "Frame", 0, "Slot", 0);
thirdReplay = sixgr.system.waveform.replayGrant( ...
    cfg, "DL", grant, [], 45, "StrictMode", true, ...
    "CompactPHYIO", true, "FastAWGNPath", false, ...
    "NoiseSeed", 8811, "ChannelSeed", 9911);
assert(thirdReplay.WaveformReplayExecuted && ...
    thirdReplay.TransmittedRNTI == 103 && ...
    replay{2}.TransmittedRNTI == 102, ...
    "Payloadless replay must retain each frozen grant's RNTI.");

missingRNTIGrant = rmfield(grant, "RNTI");
caughtMissingRNTI = false;
try
    sixgr.system.waveform.replayGrant( ...
        cfg, "DL", missingRNTIGrant, [], 45, "StrictMode", true, ...
        "CompactPHYIO", true, "FastAWGNPath", false);
catch ME
    caughtMissingRNTI = string(ME.identifier) == ...
        "sixgr:system:WaveformReplay:MissingGrantRNTI";
end
assert(caughtMissingRNTI, ...
    "A physical grant without UE scrambling identity must fail closed.");

expectedBits = double(explicitReplay.TransportBlockSize);
for badBits = {int8(zeros(expectedBits-1,1)), ...
        int8(zeros(expectedBits+1,1)), ...
        int8([2; zeros(expectedBits-1,1)])}
    caught = false;
    try
        sixgr.system.waveform.replayGrant( ...
            cfg, "DL", grant, badBits{1}, 45, "StrictMode", true, ...
            "CompactPHYIO", true, "FastAWGNPath", false);
    catch ME
        caught = any(string(ME.identifier) == [ ...
            "sixgr:system:WaveformReplay:PayloadTBSMismatch", ...
            "sixgr:system:WaveformReplay:InvalidPayloadBits"]);
    end
    assert(caught, ...
        "Explicit TB length and binary identity must fail before waveform transmission.");
end

ok = true;
end
