    string(dlFDDSpatial.CSIRSTrialTable.SpatialSignatureDomain(1)) == "transmitter" && ...
    startsWith(string(dlFDDSpatial.CSIRSTrialTable.SpatialSignatureSource(1)), ...
        "measured_csirs_receiver_channel_estimate_transmit_subspace"), ...
    ["FDD CSI-RS rows must persist the measured right-singular DL " ...
     "transmit subspace and must not borrow TDD SRS reciprocity authority."]);
