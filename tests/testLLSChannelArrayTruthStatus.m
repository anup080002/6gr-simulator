function ok = testLLSChannelArrayTruthStatus()
%TESTLLSCHANNELARRAYTRUTHSTATUS Verify channel-factory array-handling labels stay truthful.

setup6GRSimToolkit("Verbose", false);

cfgTDL = sixgr.config.defaultConfig();
cfgTDL.channel.model = "TDL";
cfgTDL.channel.tdlProfile = "TDL-C";
cfgTDL.channel.delayProfile = "TDL-C";
cfgTDL.channel.delaySpread_s = 300e-9;
cfgTDL.channel.doppler_Hz = 30;
cfgTDL.channel.nTxAnt = 4;
cfgTDL.channel.nRxAnt = 2;
cfgTDL.phy.fc_Hz = 700e6;

tdl = sixgr.channel.ChannelFactory.create(cfgTDL, ...
    "Model", "TDL-C", ...
    "SampleRate", 30.72e6, ...
    "NumTxAnt", 4, ...
    "NumRxAnt", 2, ...
    "Fc_Hz", 700e6, ...
    "Seed", 17);

assert(strcmpi(char(string(tdl.Meta.ChannelArrayModel)), "nrtdl_count_only_fading_channel"), ...
    "TDL channel metadata must disclose the count-only fading model.");
assert(strcmpi(char(string(tdl.Meta.ChannelObjectSource)), "sixgr.channel.channelfactory.localcreatetdl") && ...
    strcmpi(char(string(tdl.Meta.ChannelObjectClass)), "nrtdlchannel"), ...
    "TDL channel metadata must disclose the actual channel-object source and class.");
assert(strcmpi(char(string(tdl.Meta.ChannelArrayHandlingStatus)), "count_only_spatial_dims_no_runtime_geometry") && ...
    strcmpi(char(string(tdl.Meta.ChannelArrayHandlingBlocker)), "runtime_geometry_not_supplied_or_not_mappable_to_tdl_custom_correlation") && ...
    strcmpi(char(string(tdl.Meta.ChannelGeometryCouplingLevel)), "none_count_only_antenna_dimensions"), ...
    "TDL channel metadata must preserve the exact runtime-geometry blocker.");
assert(logical(tdl.Meta.ChannelUsesCountOnlyAntennaModel) && ~logical(tdl.Meta.ChannelUsesSameRuntimeAntennaAssumptions), ...
    "TDL channel metadata must not claim runtime-antenna-object-equivalent assumptions.");

cfgTDL.phy.bsArray = [2 2 1];
cfgTDL.phy.ueArray = [2 1 1];
cfgTDL.antenna.bs.geometry = "URA";
cfgTDL.antenna.ue.geometry = "ULA";
cfgTDL.antenna.bs.spacingLambda = [0.5 0.5];
cfgTDL.antenna.ue.spacingLambda = [0.5 0.5];
[tdlRuntime, txCorr05] = localBuildRuntimeTDL(cfgTDL, [0.5 0.5]);
[tdlRuntimeWide, txCorr08] = localBuildRuntimeTDL(cfgTDL, [0.8 0.8]);

assert(strcmpi(char(string(tdlRuntime.Meta.ChannelArrayModel)), "nrtdl_runtime_geometry_correlation_channel"), ...
    "Runtime-backed TDL metadata must disclose the reduced geometry-correlation channel model.");
assert(strcmpi(char(string(tdlRuntime.Meta.ChannelArrayHandlingStatus)), "adapted_geometry_backed_reduced_representation") && ...
    strcmpi(char(string(tdlRuntime.Meta.ChannelArrayHandlingBlocker)), "nrtdlchannel_consumes_custom_spatial_correlation_matrices_not_runtime_array_objects") && ...
    strcmpi(char(string(tdlRuntime.Meta.ChannelGeometryCouplingLevel)), "runtime_geometry_reduced_spatial_correlation"), ...
    "Runtime-backed TDL metadata must label the adapter as a reduced representation, not full array-object coupling.");
assert(~logical(tdlRuntime.Meta.ChannelUsesCountOnlyAntennaModel) && ~logical(tdlRuntime.Meta.ChannelUsesSameRuntimeAntennaAssumptions), ...
    "Runtime-backed TDL must stop reporting count-only handling without claiming full runtime-array equivalence.");
assert(strcmpi(char(string(tdlRuntime.Meta.GeometryAdapterType)), "tdl_custom_tx_rx_correlation_from_runtime_element_positions") && ...
    contains(string(tdlRuntime.Meta.GeometryAdapterLimitation), "reduced custom correlation matrices"), ...
    "Runtime-backed TDL must persist the adapter type and reduced-representation limitation.");
assert(strcmpi(char(string(tdlRuntime.Object.MIMOCorrelation)), "custom") && ...
    isequal(size(tdlRuntime.Object.TransmitCorrelationMatrix), [4 4]) && ...
    isequal(size(tdlRuntime.Object.ReceiveCorrelationMatrix), [2 2]), ...
    "Runtime-backed TDL must apply custom Tx/Rx correlation matrices to nrTDLChannel.");
assert(any(abs(txCorr05(:) - reshape(eye(4), [], 1)) > 1e-6) && ...
    any(abs(double(tdlRuntime.Object.ReceiveCorrelationMatrix(:)) - reshape(eye(2), [], 1)) > 1e-6), ...
    "Runtime-backed TDL correlation matrices must materially reflect nonzero runtime element spacing.");
assert(max(abs(txCorr05(:) - txCorr08(:))) > 1e-6, ...
    "Changing runtime antenna spacing must change the reduced TDL correlation representation.");

cfgCDL = sixgr.config.defaultConfig();
cfgCDL.channel.model = "CDL";
cfgCDL.channel.cdlProfile = "CDL-D";
cfgCDL.channel.delayProfile = "CDL-D";
cfgCDL.channel.delaySpread_s = 300e-9;
cfgCDL.channel.doppler_Hz = 30;
cfgCDL.channel.fading.profile = "CDL-D";
cfgCDL.channel.fading.model = "CDL-D";
cfgCDL.channel.nTxAnt = 8;
cfgCDL.channel.nRxAnt = 8;
cfgCDL.phy.fc_Hz = 30e9;
cfgCDL.antenna_and_array.bs_array_geometry = "ura";
cfgCDL.antenna_and_array.ue_array_geometry = "ula";
cfgCDL.antenna_and_array.polarization = "single";

cdl = sixgr.channel.ChannelFactory.create(cfgCDL, ...
    "Model", "CDL-D", ...
    "SampleRate", 30.72e6, ...
    "NumTxAnt", 8, ...
    "NumRxAnt", 8, ...
    "Fc_Hz", 30e9, ...
    "Seed", 23);

assert(strcmpi(char(string(cdl.Meta.ChannelArrayModel)), "nrcdl_config_array_shape_channel"), ...
    "CDL channel metadata must not overclaim runtime-array-object coupling.");
assert(strcmpi(char(string(cdl.Meta.ChannelObjectSource)), "sixgr.channel.channelfactory.localcreatecdl") && ...
    strcmpi(char(string(cdl.Meta.ChannelObjectClass)), "nrcdlchannel"), ...
    "CDL channel metadata must disclose the actual CDL channel-object source and class.");
assert(strcmpi(char(string(cdl.Meta.ChannelArrayHandlingStatus)), "config_array_shape_no_runtime_object_pose") && ...
    strcmpi(char(string(cdl.Meta.ChannelArrayHandlingBlocker)), "nrcdlchannel_uses_configured_array_shape_but_not_runtime_antenna_object_pose") && ...
    strcmpi(char(string(cdl.Meta.ChannelGeometryCouplingLevel)), "config_array_shape_only"), ...
    "CDL channel metadata must state that it uses config-resolved array shape rather than runtime antenna objects.");
assert(~logical(cdl.Meta.ChannelUsesCountOnlyAntennaModel) && ~logical(cdl.Meta.ChannelUsesSameRuntimeAntennaAssumptions), ...
    "CDL channel metadata must keep runtime-antenna-object coupling separate from config-array-shape handling.");

cfgCDL.phy.bsArray = [2 4 1];
cfgCDL.phy.ueArray = [8 1 1];
cfgCDL.antenna.bs.geometry = "URA";
cfgCDL.antenna.ue.geometry = "ULA";
cfgCDL.antenna.bs.spacingLambda = [0.5 0.5];
cfgCDL.antenna.ue.spacingLambda = [0.5 0.5];
bsRuntime = sixgr.rf.AntennaArrayFactory.build(cfgCDL, "bs", ...
    "arrayType", "URA", ...
    "elementSpacingLambda", [0.5 0.5]);
ueRuntime = sixgr.rf.AntennaArrayFactory.build(cfgCDL, "ue", ...
    "arrayType", "ULA", ...
    "elementSpacingLambda", [0.5 0.5]);
bsRuntimeMeta = struct( ...
    "NumRows", 2, ...
    "NumCols", 4, ...
    "NumPolarizations", 1, ...
    "NumElements", 8, ...
    "SpacingH_lambda", 0.5, ...
    "SpacingV_lambda", 0.5, ...
    "Azimuth_deg", 33, ...
    "Tilt_deg", -7);
ueRuntimeMeta = struct( ...
    "NumRows", 8, ...
    "NumCols", 1, ...
    "NumPolarizations", 1, ...
    "NumElements", 8, ...
    "SpacingH_lambda", 0.5, ...
    "SpacingV_lambda", 0.5, ...
    "Heading_deg", -12, ...
    "Tilt_deg", 0);

cdlRuntime = sixgr.channel.ChannelFactory.create(cfgCDL, ...
    "Model", "CDL-D", ...
    "SampleRate", 30.72e6, ...
    "NumTxAnt", 8, ...
    "NumRxAnt", 8, ...
    "Fc_Hz", 30e9, ...
    "Seed", 29, ...
    "TransmitAntennaRuntime", bsRuntime, ...
    "ReceiveAntennaRuntime", ueRuntime, ...
    "TransmitAntennaMeta", bsRuntimeMeta, ...
    "ReceiveAntennaMeta", ueRuntimeMeta);

assert(strcmpi(char(string(cdlRuntime.Meta.ChannelArrayModel)), "nrcdl_runtime_array_geometry_channel"), ...
    "CDL metadata must distinguish runtime-array coupling from config-only CDL shape when runtime antenna evidence is supplied.");
assert(strcmpi(char(string(cdlRuntime.Meta.ChannelArrayHandlingStatus)), "runtime_array_shape_spacing_orientation_coupled") && ...
    strlength(string(cdlRuntime.Meta.ChannelArrayHandlingBlocker)) == 0 && ...
    strcmpi(char(string(cdlRuntime.Meta.ChannelGeometryCouplingLevel)), "runtime_array_shape_spacing_orientation"), ...
    "Runtime-backed CDL must expose implemented array coupling without a blocker.");
assert(logical(cdlRuntime.Meta.ChannelUsesSameRuntimeAntennaAssumptions), ...
    "Runtime-backed CDL must disclose that the channel consumed runtime antenna assumptions.");
assert(isequal(double(cdlRuntime.Object.TransmitAntennaArray.Size(1:3)), [2 4 1]) && ...
    isequal(double(cdlRuntime.Object.ReceiveAntennaArray.Size(1:3)), [8 1 1]), ...
    "Runtime-backed CDL must use the runtime BS/UE array shapes.");
if isprop(cdlRuntime.Object, "TransmitArrayOrientation") && isprop(cdlRuntime.Object, "ReceiveArrayOrientation")
    assert(abs(double(cdlRuntime.Object.TransmitArrayOrientation(1)) - 33) < 1e-9 && ...
        abs(double(cdlRuntime.Object.TransmitArrayOrientation(2)) + 7) < 1e-9 && ...
        abs(double(cdlRuntime.Object.ReceiveArrayOrientation(1)) + 12) < 1e-9, ...
        "Runtime-backed CDL must use runtime BS azimuth/tilt and UE heading as array orientation evidence.");
end
runtimeInfo = info(cdlRuntime.Object);
assert(runtimeInfo.NumTransmitAntennas == 8 && runtimeInfo.NumReceiveAntennas == 8, ...
    "Runtime-backed CDL channel dimensions must match the runtime antenna evidence.");

cfgTR38901 = sixgr.config.defaultConfig();
cfgTR38901.channel.model = "TR38901";
cfgTR38901.channel.pathlossModel = "nrPathLoss";
cfgTR38901.channel.pathloss.model = "nrPathLoss";
cfgTR38901.channel.spatialNonStationary.enable = true;
cfgTR38901.channel.spatialNonStationary.numTxSubarrays = 2;
cfgTR38901.channel.spatialNonStationary.numRxSubarrays = 2;
cfgTR38901.channel.spatialNonStationary.pVisible = 0.5;
cfgTR38901.channel.nTxAnt = 4;
cfgTR38901.channel.nRxAnt = 2;
cfgTR38901.phy.fc_Hz = 4e9;

tr38901 = sixgr.channel.ChannelFactory.create(cfgTR38901, ...
    "Model", "TR38901", ...
    "Fc_Hz", 4e9, ...
    "NumTxAnt", 4, ...
    "NumRxAnt", 2, ...
    "Seed", 31);

assert(strcmpi(char(string(tr38901.Meta.ChannelComplianceMode)), "approximate_38901_plus"), ...
    "TR38901 metadata must expose the resolved channel compliance mode.");

haveNrPathLoss = exist("nrPathLossConfig", "class") == 8 && exist("nrPathLoss", "file") == 2;
if haveNrPathLoss
    assert(strcmpi(char(string(tr38901.Meta.PathlossExecutionBackend)), "nrpathloss_runtime_backend") && ...
        strcmpi(char(string(tr38901.Meta.PathlossTruthClassification)), "standards_backed_3gpp_large_scale_pathloss") && ...
        strcmpi(char(string(tr38901.Meta.PathlossModelSource)), "nrpathloss_runtime_backend") && ...
        strcmpi(char(string(tr38901.Meta.PathlossComplianceStatus)), "strict_38901_runtime") && ...
        ~logical(tr38901.Meta.FallbackUsedForPathloss) && ...
        strlength(string(tr38901.Meta.PathlossApproximationReason)) == 0, ...
        "TR38901 metadata must disclose that nrPathLoss is the active standards-backed runtime backend when it is available.");
else
    assert(strcmpi(char(string(tr38901.Meta.PathlossExecutionBackend)), "tr38901_closed_form_runtime_backend") && ...
        strcmpi(char(string(tr38901.Meta.PathlossTruthClassification)), "standards_backed_3gpp_closed_form_large_scale_pathloss") && ...
        strcmpi(char(string(tr38901.Meta.PathlossModelSource)), "tr38901_closed_form_equations") && ...
        strcmpi(char(string(tr38901.Meta.PathlossComplianceStatus)), "tr38901_closed_form_runtime") && ...
        ~logical(tr38901.Meta.FallbackUsedForPathloss), ...
        "TR38901 metadata must use standards-backed closed-form pathloss rather than FSPL when nrPathLoss is unavailable.");
end

assert(strcmpi(char(string(tr38901.Meta.SpatialNonStationarityTruthClassification)), "approximate_random_placeholder_visibility_masks") && ...
    strcmpi(char(string(tr38901.Meta.SpatialNonStationarityApproximationMode)), "random_visibility_masks_without_geometry_or_angle_coupling") && ...
    contains(lower(char(string(tr38901.Meta.SpatialNonStationarityApproximationReason))), "placeholder"), ...
    "Spatial non-stationarity metadata must remain explicitly labeled as a placeholder approximation.");

cfgPN = sixgr.config.defaultConfig();
cfgPN.rf.phaseNoise.enable = true;
[yPN, replay] = sixgr.link.applyWaveformImpairments(complex(ones(4096,1)), cfgPN, 30.72e6);
assert(logical(replay.PhaseNoiseConfigured) && ...
    logical(replay.PhaseNoiseApplied) && ...
    strcmpi(char(string(replay.PhaseNoiseExecutionStatus)), "applied_sample_domain_phase_noise"), ...
    "Waveform impairment replay must materialize configured phase noise in the active no-proxy waveform path.");
if strcmpi(char(string(replay.PhaseNoiseAvailableBackend)), "comm_phase_noise_runtime_backend")
    assert(strcmpi(char(string(replay.PhaseNoiseAvailableBackend)), "comm_phase_noise_runtime_backend") && ...
        strcmpi(char(string(replay.PhaseNoiseTruthClassification)), "toolbox_runtime_phase_noise_backend"), ...
        "Waveform replay must disclose the available comm.PhaseNoise backend.");
else
    assert(strcmpi(char(string(replay.PhaseNoiseAvailableBackend)), "colored_psd_phase_noise_runtime_model") && ...
        strcmpi(char(string(replay.PhaseNoiseTruthClassification)), "runtime_colored_phase_noise_model"), ...
        "Waveform replay must use the colored PSD phase-noise runtime model when Communications Toolbox is unavailable.");
end
assert(any(abs(yPN - yPN(1)) > 0), "Applied phase noise must vary over the waveform.");

ok = true;
end

function [tdlRuntime, txCorr] = localBuildRuntimeTDL(cfgTDL, spacingLambda)
cfgTDL.antenna.bs.spacingLambda = spacingLambda;
cfgTDL.antenna.ue.spacingLambda = spacingLambda;
bsRuntime = sixgr.rf.AntennaArrayFactory.build(cfgTDL, "bs", ...
    "arrayType", "URA", ...
    "elementSpacingLambda", spacingLambda);
ueRuntime = sixgr.rf.AntennaArrayFactory.build(cfgTDL, "ue", ...
    "arrayType", "ULA", ...
    "elementSpacingLambda", spacingLambda);
bsRuntimeMeta = struct( ...
    "NumRows", 2, ...
    "NumCols", 2, ...
    "NumPolarizations", 1, ...
    "NumElements", 4, ...
    "SpacingH_lambda", spacingLambda(1), ...
    "SpacingV_lambda", spacingLambda(2), ...
    "Azimuth_deg", 15, ...
    "Tilt_deg", -3);
ueRuntimeMeta = struct( ...
    "NumRows", 2, ...
    "NumCols", 1, ...
    "NumPolarizations", 1, ...
    "NumElements", 2, ...
    "SpacingH_lambda", spacingLambda(1), ...
    "SpacingV_lambda", spacingLambda(2), ...
    "Heading_deg", -5, ...
    "Tilt_deg", 0);

tdlRuntime = sixgr.channel.ChannelFactory.create(cfgTDL, ...
    "Model", "TDL-C", ...
    "SampleRate", 30.72e6, ...
    "NumTxAnt", 4, ...
    "NumRxAnt", 2, ...
    "Fc_Hz", 700e6, ...
    "Seed", 19, ...
    "TransmitAntennaRuntime", bsRuntime, ...
    "ReceiveAntennaRuntime", ueRuntime, ...
    "TransmitAntennaMeta", bsRuntimeMeta, ...
    "ReceiveAntennaMeta", ueRuntimeMeta);
txCorr = double(tdlRuntime.Object.TransmitCorrelationMatrix);
end
