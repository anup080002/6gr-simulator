function ok = testArtifactEvidenceIdentity()
%TESTARTIFACTEVIDENCEIDENTITY Cross-scenario/component evidence fails closed.

cfg = struct( ...
    "scenario_id", "identity_fixture", ...
    "frequency", struct("center_frequency_hz", 3.5e9, ...
        "channel_bandwidth_mhz", 100), ...
    "numerology", struct("scs_khz", 30));
configHash = sixgr.integration.IntegrationHash.data(cfg);
expected = struct( ...
    "ScenarioID", "identity_fixture", ...
    "RunID", "run-001", ...
    "ExecutionID", "exec-001", ...
    "ConfigHash", configHash, ...
    "EvidenceScope", "in_path", ...
    "CenterFrequencyHz", 3.5e9, ...
    "BandwidthHz", 100e6, ...
    "SubcarrierSpacingHz", 30e3, ...
    "NormalizedConfig", cfg);
T = table( ...
    repmat("identity_fixture",2,1), repmat("run-001",2,1), ...
    repmat("exec-001",2,1), repmat(configHash,2,1), ...
    repmat("in_path",2,1), repmat(3.5e9,2,1), ...
    repmat(100e6,2,1), repmat(30e3,2,1), (1:2).', ...
    'VariableNames', {'ScenarioID','RunID','ExecutionID','ConfigHash', ...
    'EvidenceScope','CenterFrequencyHz','BandwidthHz','SubcarrierSpacingHz','TrialID'});
audit = sixgr.artifact.validateEvidenceIdentity(T, expected, "identity.csv");
assert(height(audit) == 8 && all(audit.Pass));

anchor = T;
anchor.EvidenceScope(:) = "component_anchor";
localExpect(@() sixgr.artifact.validateEvidenceIdentity( ...
    anchor, expected, "anchor.csv"), ...
    "sixgr:artifact:EvidenceIdentityMismatch");

wrongRadio = T;
wrongRadio.CenterFrequencyHz(:) = 4e9;
localExpect(@() sixgr.artifact.validateEvidenceIdentity( ...
    wrongRadio, expected, "wrong_radio.csv"), ...
    "sixgr:artifact:RadioIdentityMismatch");

wrongHash = expected;
wrongHash.ConfigHash = string(repmat('0',1,64));
localExpect(@() sixgr.artifact.validateEvidenceIdentity( ...
    T, wrongHash, "wrong_hash.csv"), ...
    "sixgr:artifact:NormalizedConfigHashMismatch");

missing = removevars(T, "EvidenceScope");
localExpect(@() sixgr.artifact.validateEvidenceIdentity( ...
    missing, expected, "missing_scope.csv"), ...
    "sixgr:artifact:IdentityColumnMissing");

ok = true;
fprintf("PASS testArtifactEvidenceIdentity: scenario, hash, scope and radio identity are exact.\n");
end

function localExpect(fcn, identifier)
try
    fcn();
    error("testArtifactEvidenceIdentity:ExpectedFailure", ...
        "Expected %s.", identifier);
catch ME
    assert(strcmp(ME.identifier, identifier), ...
        "Expected %s, received %s: %s", identifier, ME.identifier, ME.message);
end
end
