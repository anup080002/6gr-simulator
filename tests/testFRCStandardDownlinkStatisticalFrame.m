function ok = testFRCStandardDownlinkStatisticalFrame()
%TESTFRCSTANDARDDOWNLINKSTATISTICALFRAME Decode from propagated FRC frames.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

qpsk = sixgr.conformance.runFRCPoint( ...
    "dl_r_pdsch_1_1_4_fdd_awgn", "awgn_static_1x2", ...
    "SNRGrid_dB", 3.2, "ExecutionProfile", "smoke", ...
    "MinTransportBlocks", 1, "MaxTransportBlocks", 1, ...
    "BatchSize", 1, "EvaluateSymmetricRegression", false, ...
    "RequireExactStandardExecution", true, ...
    "RequireExactDataChannelExecution", true, ...
    "PrintTable", false, "Verbose", false);
assert(height(qpsk.Sweep) == 1 && qpsk.Sweep.TransportBlocks == 1);
detail = qpsk.PointDetails{1};
localAssertFrame(detail, 1, 0);
assert(qpsk.ReferencePointNormative && ...
    qpsk.ReferencePointSemantics == ...
        "one_sided_required_snr_complete_standard_frc_execution");
% A one-TB smoke sample must never be promoted to a normative pass.
assert(~qpsk.NormativePass && ~qpsk.StatisticallyQualified);

qam64 = sixgr.conformance.runFRCPoint( ...
    "dl_r_pdsch_1_3_6_fdd_atg_awgn", "atg_awgn_220hz_2x2", ...
    "SNRGrid_dB", 13.6, "ExecutionProfile", "smoke", ...
    "MinTransportBlocks", 1, "MaxTransportBlocks", 1, ...
    "BatchSize", 1, "EvaluateSymmetricRegression", false, ...
    "RequireExactStandardExecution", true, ...
    "RequireExactDataChannelExecution", true, ...
    "PrintTable", false, "Verbose", false);
required = double(qam64.RequiredSNR_dB);
requiredIndex = find(abs(qam64.Sweep.SNR_dB-required) < 1e-12, 1);
detail = qam64.PointDetails{requiredIndex};
% This FDD FRC uses the four-process round-robin timing required by the
% catalog.  Retransmissions of the same TB therefore occupy slots
% 1,5,9,13 of the 20-slot standard period, not four adjacent slots.
localAssertFrame(detail, [1 5 9 13], [0 2 3 1]);
assert(isequal(double(detail.Propagation.StandardDownlinkFrame.TargetAbsoluteSlot(:).'), ...
    double(detail.Propagation.StandardDownlinkFrame.TargetSlotWithinPeriod(:).')), ...
    "The materialized FRC frame must use the exact HARQ timeline slots.");
assert(detail.FirstTransmission.StandardDownlinkAuxiliary.PDCCH.ScheduledLayers == 1);
assert(all(abs(detail.FirstTransmission.StandardDownlinkAuxiliary.PDCCH.PrecoderPower-1) < 1e-12));

ok = true;
end

function localAssertFrame(detail, slots, rv)
frame = detail.Propagation.StandardDownlinkFrame;
assert(frame.Materialized && frame.NoProxyOrFallbackUsed);
assert(isequal(double(frame.TargetSlotWithinPeriod(:).'), double(slots)));
assert(isequal(double(frame.RVSequence(:).'), double(rv)));
assert(isequal(double(frame.FrameGridSize(1:2)), [624 280]));
assert(frame.WaveformSize(1) == 307200);
assert(frame.SampleRate_Hz == 15.36e6);
assert(strlength(frame.FrameGridSHA256) == 64 && ...
    strlength(frame.FrameWaveformSHA256) == 64);
assert(~detail.TruthUnavailableRescueUsed && ...
    ~detail.ProxyUsed && ~detail.FallbackUsed);
assert(detail.FirstTransmission.StandardDownlinkAuxiliary.PDCCH.DCIContextDerived);
end
