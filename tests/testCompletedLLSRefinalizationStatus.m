function ok = testCompletedLLSRefinalizationStatus()
%TESTCOMPLETEDLLSREFINALIZATIONSTATUS Explicit completed recovery may pass.

status = struct( ...
    "RunCompletion", "completed_with_failures", ...
    "ResultOk", false, ...
    "PartialOk", true, ...
    "RequiredFailureCount", 1, ...
    "RequiredFailedCases", "pending", ...
    "FailingCaseCount", 1, ...
    "CaseOk", false, ...
    "ErrorSource", "old", ...
    "ErrorIdentifier", "old", ...
    "ErrorMessage", "old", ...
    "StatusAuthority", "pending", ...
    "AuthoritativeStatusSource", "pending", ...
    "StatusNotes", "pending");
root = struct("ResultOk", true, "ResultStatusReason", "all_required_root_gates_passed");
verdict = struct("Ok", true, "RuntimeTruthContractOk", true, ...
    "Failures", strings(0, 1), "ResultStatus", root);

failedRecovery = sixgr.truth.applyCompletedRefinalizationVerdict( ...
    status, verdict, "failed_recovery");
assert(~logical(failedRecovery.ResultOk), ...
    "Default failed-run recovery must never promote a failed run.");

completed = sixgr.truth.applyCompletedRefinalizationVerdict( ...
    status, verdict, "completed_run_refinalization");
assert(logical(completed.ResultOk) && completed.RunCompletion == "completed" && ...
    completed.RequiredFailureCount == 0 && isempty(completed.RequiredFailedCases), ...
    "A completed run with a clean re-finalization verdict was not promoted.");

badVerdict = verdict;
badVerdict.Ok = false;
badVerdict.RuntimeTruthContractOk = false;
badVerdict.Failures = "missing_real_evidence";
badVerdict.ResultStatus.ResultOk = false;
rejected = sixgr.truth.applyCompletedRefinalizationVerdict( ...
    status, badVerdict, "completed_run_refinalization");
assert(~logical(rejected.ResultOk) && rejected.RequiredFailureCount == 1 && ...
    any(rejected.RequiredFailedCases == "missing_real_evidence"), ...
    "Completed-run re-finalization did not remain fail-closed on a bad verdict.");

ok = true;
end
