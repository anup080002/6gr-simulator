function ok = testFRCReferenceQualificationPublisher()
%TESTFRCREFERENCEQUALIFICATIONPUBLISHER Diagnostic evidence cannot qualify.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
root = tempname;
mkdir(root);
cleanup = onCleanup(@() rmdir(root, "s")); %#ok<NASGU>

out = sixgr.conformance.runReferenceQualification(root, ...
    "Profile", "diagnostic", ...
    "EntryIds", "dl_r_pdsch_1_1_4_fdd_awgn", ...
    "MinTransportBlocks", 1, "MaxTransportBlocks", 2, ...
    "BatchSize", 1, "MinimumBlockErrors", 0, "Verbose", false);
assert(isfile(out.OutputPath) && endsWith(out.OutputPath, "frc_reference_diagnostic.csv"), ...
    "Diagnostic FRC execution must use the diagnostic-only artifact name.");
assert(~isfile(fullfile(root,"reports","csv","frc_reference_qualification.csv")), ...
    "A bounded diagnostic FRC execution must not materialize qualification evidence.");
assert(height(out.Table) == 1 && out.Table.ExecutionAttempted(1) && ...
    ~out.Table.StatisticallyQualified(1) && ~out.Table.Pass(1), ...
    "Diagnostic FRC execution must remain explicitly unqualified.");
assert(out.Table.EvidenceClass(1) == ...
        "ACTUAL_FRC_SELECTED_DATA_CHANNEL_TRUTH_EXECUTION", ...
    ["Diagnostic rows must identify the actual selected data-channel " ...
    "truth source without claiming a complete FRC waveform."]);
assert(~out.Table.FullStandardExecutionExact(1) && ...
    ~out.Table.SymmetricRegressionRequired(1), ...
    ["The qualification publisher must disclose incomplete full-standard " ...
    "execution and keep the nonnormative symmetric crossing optional."]);
localAssertMasterPolicy("master_sinr_sweep.yaml", true);
localAssertMasterPolicy("master_geometry_based.yaml", false);
ok = true;
end

function localAssertMasterPolicy(fileName, expectedEnabled)
scfg = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    pwd, "simulator", "configs", "scenarios", fileName));
base = "validation.independent_reference_qualification.";
assert(logical(scfg.get(base + "enabled", false)) == expectedEnabled && ...
    logical(scfg.get(base + "required_for_production", false)) && ...
    string(scfg.get(base + "profile", "")) == "full", ...
    "%s must expose an explicit fail-closed full FRC publication policy.", fileName);
entries = string(scfg.get(base + "entry_ids", strings(0,1)));
required = ["dl_r_pdsch_1_1_4_fdd_awgn"; ...
    "dl_r_pdsch_1_3_6_fdd_atg_awgn"; ...
    "dl_r_pdsch_1_4_1_fdd_atg_awgn"; ...
    "ul_g_fr1_a3a_1_awgn"; ...
    "ul_g_fr1_a13_1_atg_awgn"];
assert(all(ismember(required, entries(:))) && ...
    double(scfg.get(base + "min_transport_blocks", 0)) >= 1000 && ...
    double(scfg.get(base + "minimum_block_errors", 0)) >= 100, ...
    "%s must enumerate the mandatory DL/UL FRC anchors and publication sample floor.", fileName);
assert(abs(double(scfg.get(base + "confidence_level", NaN)) - 0.95) < eps && ...
    ~logical(scfg.get(base + ...
    "require_symmetric_regression_for_production", true)), ...
    ["%s must use the one-sided 3GPP operating-point requirement and " ...
    "keep symmetric crossing as a nonnormative diagnostic."], fileName);
sampling = scfg.get(base + "sampling_by_entry", struct([]));
assert(isstruct(sampling) && numel(sampling) == numel(entries) && ...
    isequal(string({sampling.entry_id}).', entries(:)), ...
    "%s must provide one explicit sampling policy per mandatory FRC.", fileName);
rare = ismember(string({sampling.entry_id}), ...
    ["dl_r_pdsch_1_1_4_fdd_awgn","ul_g_fr1_a3a_1_awgn"]);
assert(all(double([sampling(rare).max_transport_blocks]) >= 300000), ...
    "%s rare-error FRCs require the 95%% one-sided zero-error sample floor.", fileName);
end
