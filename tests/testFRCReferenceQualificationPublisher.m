function ok = testFRCReferenceQualificationPublisher()
%TESTFRCREFERENCEQUALIFICATIONPUBLISHER Diagnostic evidence cannot qualify.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
% Exercise the public publisher through a relative run root.  Absolute-only
% fixtures did not detect the former run/run/reports source-path duplication.
rootAbsolute = tempname(pwd);
[~, root] = fileparts(rootAbsolute);
mkdir(root);
cleanup = onCleanup(@() rmdir(root, "s")); %#ok<NASGU>

out = sixgr.conformance.runReferenceQualification(root, ...
    "Profile", "diagnostic", ...
    "EntryIds", "dl_r_pdsch_1_1_4_fdd_awgn", ...
    "MinTransportBlocks", 1, "MaxTransportBlocks", 2, ...
    "BatchSize", 1, "MinimumBlockErrors", 0, "Verbose", false);
assert(isfile(out.OutputPath) && endsWith(out.OutputPath, "frc_reference_diagnostic.csv"), ...
    "Diagnostic FRC execution must use the diagnostic-only artifact name.");
assert(startsWith(string(out.OutputPath), ...
    sixgr.util.canonicalPath(root) + string(filesep)), ...
    "A relative qualification run root must be canonicalized exactly once.");
assert(~isfile(fullfile(root,"reports","csv","frc_reference_qualification.csv")), ...
    "A bounded diagnostic FRC execution must not materialize qualification evidence.");
assert(height(out.Table) == 1 && out.Table.ExecutionAttempted(1) && ...
    ~out.Table.StatisticallyQualified(1) && ~out.Table.Pass(1), ...
    "Diagnostic FRC execution must remain explicitly unqualified.");
requiredPoint = out.EntryResults{1}.RequiredPoint;
assert(out.Table.SchemaVersion(1) == ...
    "sixgr.conformance.reference_qualification/v6" && ...
    out.Table.TransportBlocks(1) == requiredPoint.TransportBlocks(1) && ...
    out.Table.BlockErrors(1) == requiredPoint.FailedTransportBlocks(1) && ...
    out.Table.Transmissions(1) == requiredPoint.Transmissions(1) && ...
    out.Table.SweepTransportBlocks(1) == ...
        sum(out.EntryResults{1}.Sweep.TransportBlocks) && ...
    out.Table.PointEstimate(1) == requiredPoint.MetricEstimate(1) && ...
    out.Table.OneSidedLower(1) == requiredPoint.OneSidedLower(1) && ...
    out.Table.OneSidedUpper(1) == requiredPoint.OneSidedUpper(1) && ...
    strlength(out.Table.SourceGitCommit(1)) == 40 && ...
    strlength(out.Table.SourceStateSHA256(1)) == 64 && ...
    ~out.Table.ProxyUsed(1) && ~out.Table.FallbackUsed(1) && ...
    out.Table.ApproximationMode(1) == "none", ...
    ["The versioned summary must bind its decision to the required-SNR " ...
    "point, retain separate sweep totals, and expose truthful source lineage."]);
assert(~out.Table.MeasuredSNRAvailable(1) && ...
    out.Table.CrossingStatus(1) == "not_evaluated_by_configuration" && ...
    out.Table.Transmissions(1) >= out.Table.TransportBlocks(1) && ...
    out.Table.FailedTransmissionAttempts(1) == ...
    out.Table.Transmissions(1) - ...
    sum(out.EntryResults{1}.Sweep.DeliveredTransportBlocks), ...
    ["Qualification summaries must disclose why measured crossing fields " ...
    "are unavailable and expose failed HARQ transmission attempts."]);
if logical(out.EntryResults{1}.ReferencePointPointEstimatePass)
    assert(contains(out.Table.FailureReason(1), ...
        "observed_pass_not_statistically_qualified") && ...
        ~contains(out.Table.FailureReason(1), ...
        "one_sided_reference_point_failed"), ...
        ["A point-estimate pass with insufficient TBs must be reported as " ...
        "statistically unqualified, not as a physical reference failure."]);
end
assert(out.Table.EvidenceClass(1) == ...
        "ACTUAL_FRC_FULL_STANDARD_TRUTH_EXECUTION", ...
    "Diagnostic rows must identify the actual complete FRC waveform " + ...
    "while remaining statistically unqualified.");
assert(out.Table.FullStandardExecutionExact(1) && ...
    ~out.Table.SymmetricRegressionRequired(1), ...
    "The qualification publisher must disclose exact full-standard " + ...
    "execution and keep the nonnormative symmetric crossing optional.");
assert(isfile(out.PointArtifacts.PointCSV) && ...
    numel(out.PointArtifacts.ImagePaths) == 1 && ...
    isfile(out.PointArtifacts.ImagePaths(1)) && ...
    endsWith(lower(out.PointArtifacts.ImagePaths(1)), ".png") && ...
    isfile(out.PointArtifacts.PlotLineageCSV), ...
    "The FRC publisher must create canonical point CSV and raster PNG evidence.");
points = readtable(out.PointArtifacts.PointCSV, "TextType", "string");
assert(height(points) == height(out.EntryResults{1}.Sweep) && ...
    all(points.TransportBlocks > 0) && ...
    all(~logical(points.ProxyUsed)) && ...
    all(~logical(points.FallbackUsed)) && ...
    all(points.ApproximationMode == "none"), ...
    "Published FRC points must be populated actual-waveform truth rows.");
requiredAuditColumns = [ ...
    "StandardDocument","StandardVersion","StandardRelease", ...
    "StandardSourceURL","FRCDefinitionClause","FRCDefinitionTable", ...
    "RequirementClause","RequirementTables","ConfidenceLevel", ...
    "RequiredQualificationTransportBlocks","ConfidenceSamplingPlan", ...
    "ObservedConfidenceBoundSupportsPass", ...
    "ExperimentSeed", ...
    "FailedTransmissionAttempts", ...
    "StatisticalUnit", ...
    "ConfiguredCyclicPrefix","EffectiveCyclicPrefix", ...
    "ConfiguredSubcarrierSpacing_kHz", ...
    "EffectiveSubcarrierSpacing_kHz", ...
    "ConfiguredMappingType","EffectiveMappingType", ...
    "ConfiguredSymbolStart","ConfiguredSymbolLength", ...
    "EffectiveSymbolStart","EffectiveSymbolLength", ...
    "ConfiguredDMRSSymbolIndices","EffectiveDMRSSymbolIndices", ...
    "RuntimePhysicalConfigurationExact", ...
    "RuntimePhysicalConfigurationSource", ...
    "ConfiguredModulation","ConfiguredTargetCodeRate", ...
    "EffectiveTargetCodeRate","ConfiguredTBSBits","EffectiveTBSBits", ...
    "ConfiguredCodedBitsPerSlot","EffectiveCodedBitsPerSlot", ...
    "ConfiguredLayers","EffectiveLayers","InjectedCFO_Hz", ...
    "EstimatedCFO_Hz","CFOCorrectionApplied_Hz", ...
    "ResidualCFOEstimated_Hz","ResidualCFOPhysical_Hz", ...
    "CFOPhysicalClosureError_Hz","CFOEstimateSource", ...
    "ResidualCFOEstimateSource","NoiseVarSource","DecoderNoiseVar", ...
    "PostEqSINR_dB","LastTBReceiverOk","LastTBCRCError", ...
    "ChannelExecutionMode","ChannelChunkSlots","ChannelChunkSamples", ...
    "ChannelCallCount","ChannelMaximumInputRows", ...
    "ChannelFullSequenceProcessed"];
assert(all(ismember(requiredAuditColumns, string(points.Properties.VariableNames))), ...
    "The canonical point CSV must expose configured/effective PHY and CFO evidence.");
assert(all(points.ConfiguredModulation == "QPSK") && ...
    all(lower(points.ConfiguredCyclicPrefix) == "normal") && ...
    all(lower(points.EffectiveCyclicPrefix) == "normal") && ...
    all(points.ConfiguredSubcarrierSpacing_kHz == ...
        points.EffectiveSubcarrierSpacing_kHz) && ...
    all(points.ConfiguredMappingType == "A") && ...
    all(points.EffectiveMappingType == "A") && ...
    all(points.ConfiguredSymbolStart == 2) && ...
    all(points.ConfiguredSymbolLength == 12) && ...
    all(points.EffectiveSymbolStart == 2) && ...
    all(points.EffectiveSymbolLength == 12) && ...
    all(points.RuntimePhysicalConfigurationExact) && ...
    all(points.RuntimePhysicalConfigurationSource == ...
    "materialized_truth_transmitter_objects") && ...
    all(points.StandardDocument == "3GPP TS 38.101-4") && ...
    all(points.StandardVersion == "18.11.0") && ...
    all(points.StandardRelease == 18) && ...
    all(points.RequirementClause == "5.2.2.1.5") && ...
    all(points.RequirementTables == "5.2.2.1.5-3") && ...
    all(abs(points.ConfidenceLevel - 0.95) <= eps) && ...
    all(points.RequiredQualificationTransportBlocks >= 299572) && ...
    all(points.ExperimentSeed == 38104) && ...
    all(points.StatisticalUnit == ...
    "independently_sampled_transport_block") && ...
    all(abs(points.ConfiguredTargetCodeRate - ...
    points.EffectiveTargetCodeRate) <= 1e-12) && ...
    all(points.ConfiguredTBSBits == points.EffectiveTBSBits) && ...
    all(points.ConfiguredCodedBitsPerSlot == ...
    points.EffectiveCodedBitsPerSlot) && ...
    all(points.FailedTransmissionAttempts == ...
    points.Transmissions - points.DeliveredTransportBlocks) && ...
    all(points.ConfiguredLayers == points.EffectiveLayers) && ...
    all(isfinite(points.EstimatedCFO_Hz)) && ...
    all(isfinite(points.ResidualCFOEstimated_Hz)) && ...
    all(points.CFOPhysicalClosureError_Hz <= 1e-12) && ...
    all(strlength(points.CFOEstimateSource) > 0) && ...
    all(strlength(points.ResidualCFOEstimateSource) > 0) && ...
    all(strlength(points.NoiseVarSource) > 0) && ...
    all(isfinite(points.DecoderNoiseVar)) && ...
    all(isfinite(points.PostEqSINR_dB)) && ...
    all(logical(points.LastTBReceiverOk)) && ...
    all(~logical(points.LastTBCRCError)), ...
    "Configured/effective PHY values or receiver CFO/noise evidence are inconsistent.");
lineage = readtable(out.PointArtifacts.PlotLineageCSV, "TextType", "string", ...
    "VariableNamingRule", "preserve", "Delimiter", ",");
imageInfo = imfinfo(out.PointArtifacts.ImagePaths(1));
assert(height(lineage) == 1 && lineage.Status(1) == "pass" && ...
    lineage.SourceExists(1) && lineage.ImageExists(1) && ...
    startsWith(lineage.SourceCSV(1), "reports/csv/frc_reference_points/") && ...
    ~contains(lineage.SourceCSV(1), replace(string(root), "\", "/")) && ...
    lineage.MimeType(1) == "image/png" && ...
    strlength(lineage.SourceCSV_SHA256(1)) == 64 && ...
    strlength(lineage.ImageSHA256(1)) == 64 && ...
    imageInfo.Width >= 1200 && imageInfo.Height >= 675, ...
    "FRC PNG lineage, hashes, MIME type, or dimensions are incomplete.");
assert(all(ismember(["Metric","YScale","ZeroEstimatePlotFloor", ...
    "ZeroEstimateCount","PlotSemantics"], ...
    string(lineage.Properties.VariableNames))) && ...
    lineage.Metric(1) == "block_error_rate" && ...
    lineage.YScale(1) == "log" && ...
    isfinite(lineage.ZeroEstimatePlotFloor(1)) && ...
    lineage.ZeroEstimatePlotFloor(1) > 0 && ...
    lineage.ZeroEstimateCount(1) >= 0 && ...
    strlength(lineage.PlotSemantics(1)) > 0, ...
    ["Rare-error FRC charts must disclose their logarithmic scale and " ...
    "zero-estimate plotting floor without modifying the source CSV."]);
visualIntegrity = sixgr.visual.verifyVisualArtifacts(root, table());
frcImageRelative = replace(string(lineage.ImagePath(1)), "\", "/");
frcVisualMask = string(visualIntegrity.ArtifactPath) == frcImageRelative;
assert(nnz(frcVisualMask) == 1 && ...
    logical(visualIntegrity.IsManifestRow(frcVisualMask)) && ...
    logical(visualIntegrity.IntegrityOk(frcVisualMask)) && ...
    any(string(visualIntegrity.FailureCode(frcVisualMask)) == ["","ok"]), ...
    "The terminal visual verifier must import FRC component lineage " + ...
    "as a comma-delimited schema and accept its exact CSV/image hashes.");
localAssertMasterPolicy("master_sinr_sweep.yaml", true);
localAssertMasterPolicy("master_geometry_based.yaml", false);
ok = true;
end

function localAssertMasterPolicy(fileName, expectedEnabled)
scfg = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    pwd, "simulator", "configs", "scenarios", fileName));
base = "validation.independent_reference_qualification.";
assert(logical(scfg.get(base + "enabled", false)) == expectedEnabled && ...
    logical(scfg.get(base + "required_for_production", false)) && ...
    string(scfg.get(base + "profile", "")) == "full", ...
    "%s must expose an explicit fail-closed full FRC publication policy.", fileName);
entries = string(scfg.get(base + "entry_ids", strings(0,1)));
required = ["dl_r_pdsch_1_1_4_fdd_awgn"; ...
    "dl_r_pdsch_1_3_6_fdd_atg_awgn"; ...
    "dl_r_pdsch_1_4_1_fdd_atg_awgn"; ...
    "ul_g_fr1_a3a_1_awgn"; ...
    "ul_g_fr1_a13_1_atg_awgn"];
assert(all(ismember(required, entries(:))) && ...
    double(scfg.get(base + "min_transport_blocks", 0)) >= 1000 && ...
    double(scfg.get(base + "minimum_block_errors", 0)) >= 100, ...
    "%s must enumerate the mandatory DL/UL FRC anchors and publication sample floor.", fileName);
assert(abs(double(scfg.get(base + "confidence_level", NaN)) - 0.95) < eps && ...
    double(scfg.get(base + "seed", NaN)) == 38104 && ...
    ~logical(scfg.get(base + ...
    "require_symmetric_regression_for_production", true)), ...
    ["%s must use the one-sided 3GPP operating-point requirement and " ...
    "keep symmetric crossing as a nonnormative diagnostic."], fileName);
sampling = scfg.get(base + "sampling_by_entry", struct([]));
assert(isstruct(sampling) && numel(sampling) == numel(entries) && ...
    isequal(string({sampling.entry_id}).', entries(:)), ...
    "%s must provide one explicit sampling policy per mandatory FRC.", fileName);
rare = ismember(string({sampling.entry_id}), ...
    ["dl_r_pdsch_1_1_4_fdd_awgn","ul_g_fr1_a3a_1_awgn"]);
assert(all(double([sampling(rare).max_transport_blocks]) >= 300000), ...
    "%s rare-error FRCs require the 95%% one-sided zero-error sample floor.", fileName);
rank4 = sampling(string({sampling.entry_id}) == ...
    "dl_r_pdsch_1_2_4_fdd_tdla30_10");
if any(entries == "dl_r_pdsch_1_2_4_fdd_tdla30_10")
    assert(isscalar(rank4) && isfield(rank4, "parallel_workers") && ...
        double(rank4.parallel_workers) == 1 && ...
        isfield(rank4, "channel_chunk_slots") && ...
        double(rank4.channel_chunk_slots) == 1, ...
        ["%s must serialize the memory-intensive rank-4 TDL-A FRC via " ...
        "the per-entry YAML execution policy."], fileName);
end
end
