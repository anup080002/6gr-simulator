function ok = testPRACHOccasionResolver()
%TESTPRACHOCCASIONRESOLVER Complete table coverage and shared timing use.

setup6GRSimToolkit("Verbose", false);
localVerifyEveryConfigurationTableRow();

representatives = { ...
    struct("Range", "FR1", "Duplex", "FDD", "Index", 16, ...
        "CarrierSCS", 15, "Grid", 52, "PRACHSCS", 1.25), ...
    struct("Range", "FR1", "Duplex", "TDD", "Index", 80, ...
        "CarrierSCS", 30, "Grid", 51, "PRACHSCS", 30), ...
    struct("Range", "FR2-1", "Duplex", "TDD", "Index", 0, ...
        "CarrierSCS", 120, "Grid", 66, "PRACHSCS", 120), ...
    struct("Range", "FR2-2", "Duplex", "TDD", "Index", 0, ...
        "CarrierSCS", 120, "Grid", 66, "PRACHSCS", 480)};

for i = 1:numel(representatives)
    spec = representatives{i};
    actual = localResolve(spec);
    assert(actual.ResolvedValid && ~actual.FallbackUsed && ...
        ~actual.UnknownIndexDefaulted, ...
        "Representative %s/%s/%d did not resolve strictly.", ...
        spec.Range, spec.Duplex, spec.Index);
    assert(~isempty(actual.Occasions), ...
        "Representative %s/%s/%d returned no occasions.", ...
        spec.Range, spec.Duplex, spec.Index);
    assert(actual.TableRow.ConfigurationIndex == spec.Index, ...
        "Resolver selected the wrong PRACH table row.");
    assert(actual.Format == actual.TableRow.PreambleFormat, ...
        "Resolved PRACH format differs from the pinned table.");
    assert(all(actual.Occasions.IndexCount > 0) && ...
        all(actual.Occasions.SymbolCount > 0), ...
        "Canonical PRACH occasion was not materialized by the Toolbox.");
    assert(all(actual.Occasions.ULAvailable), ...
        "Unconstrained representative PRACH occasion was marked unavailable.");
end

% A two-PRACH-slot-per-subframe row exercises ActivePRACHSlot. The
% Toolbox reports SymbolLocation=14 for the second active slot, but the
% carrier-grid allocation starts at symbol zero of that carrier slot.
fdm = sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
    "FrequencyRange", "FR1", "DuplexMode", "TDD", ...
    "ConfigurationIndex", 167, ...
    "CarrierSubcarrierSpacingKHz", 30, "NSizeGrid", 100, ...
    "PRACHSubcarrierSpacingKHz", 30, "Msg1FDM", 4);
assert(all(fdm.Occasions.StartSymbol >= 0 & ...
    fdm.Occasions.StartSymbol + fdm.Occasions.DurationSymbols <= 14), ...
    "ActivePRACHSlot was not normalized onto the carrier-slot grid.");
assert(all(fdm.Occasions.StartSymbol == 0) && ...
    all(fdm.Occasions.DurationSymbols == 12), ...
    "Configuration 167 carrier-symbol occupancy differs from nrPRACHIndices.");
for ordinal = unique(fdm.Occasions.PRACHSlot).'
    rows = fdm.Occasions(fdm.Occasions.PRACHSlot == ordinal, :);
    assert(isequal(rows.FrequencyIndex(:).', 0:3) && ...
        isequal(rows.FrequencyStart(:).', [0, 12, 24, 36]), ...
        "msg1-FDM occasions do not expose distinct Toolbox PRB sets.");
end

% The scan interval is the LCM of the PRACH repetition and the runtime TDD
% direction-map period. A DL row that is reached only in the second PRACH
% cycle must still reject the configuration.
basePeriod = fdm.BasePeriodCarrierSlots;
nonDividingPeriod = basePeriod + 1;
lcmMap = repmat("U", nonDividingPeriod, 14);
laterSlot = fdm.Occasions.AbsoluteSlot(1) + basePeriod;
lcmMap(mod(laterSlot, nonDividingPeriod) + 1, :) = "D";
localAssertError(@() sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
    "FrequencyRange", "FR1", "DuplexMode", "TDD", ...
    "ConfigurationIndex", 167, ...
    "CarrierSubcarrierSpacingKHz", 30, "NSizeGrid", 100, ...
    "PRACHSubcarrierSpacingKHz", 30, ...
    "CommonDirection", lcmMap), ...
    "sixgr:phy:frame:PRACHOccasionNotULAvailable");

localAssertError(@() sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
    "FrequencyRange", "FR1", "DuplexMode", "FDD", ...
    "ConfigurationIndex", 256, "CarrierSubcarrierSpacingKHz", 15, ...
    "NSizeGrid", 52, "PRACHSubcarrierSpacingKHz", 1.25), ...
    "sixgr:phy:frame:InvalidPRACHConfigurationIndex");
localAssertError(@() sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
    "FrequencyRange", "FR2-1", "DuplexMode", "FDD", ...
    "ConfigurationIndex", 0, "CarrierSubcarrierSpacingKHz", 120, ...
    "NSizeGrid", 66, "PRACHSubcarrierSpacingKHz", 120), ...
    "sixgr:phy:frame:InvalidPRACHFrequencyDuplexContext");

% Configuration 16/FDD occurs in subframe 1 and spans a complete 15-kHz
% carrier slot.  Fixed DL and unresolved flexible maps must both fail.
commonDL = repmat("D", 20, 14);
localAssertError(@() sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
    "FrequencyRange", "FR1", "DuplexMode", "FDD", ...
    "ConfigurationIndex", 16, "CarrierSubcarrierSpacingKHz", 15, ...
    "NSizeGrid", 52, "PRACHSubcarrierSpacingKHz", 1.25, ...
    "CommonDirection", commonDL), ...
    "sixgr:phy:frame:PRACHOccasionNotULAvailable");
commonFlex = repmat("F", 20, 14);
localAssertError(@() sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
    "FrequencyRange", "FR1", "DuplexMode", "FDD", ...
    "ConfigurationIndex", 16, "CarrierSubcarrierSpacingKHz", 15, ...
    "NSizeGrid", 52, "PRACHSubcarrierSpacingKHz", 1.25, ...
    "CommonDirection", commonFlex), ...
    "sixgr:phy:frame:PRACHFlexibleSymbolUnresolved");
resolvedUL = repmat("U", 20, 14);
flexResult = sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
    "FrequencyRange", "FR1", "DuplexMode", "FDD", ...
    "ConfigurationIndex", 16, "CarrierSubcarrierSpacingKHz", 15, ...
    "NSizeGrid", 52, "PRACHSubcarrierSpacingKHz", 1.25, ...
    "CommonDirection", commonFlex, "ResolvedDirection", resolvedUL);
assert(all(flexResult.Occasions.ULAvailable), ...
    "Explicit UL runtime resolution did not enable flexible PRACH symbols.");

cfg = localSharedConfig();
mapped = sixgr.rach.mapPRACHToOccasion(cfg, "OccasionIndex", 1);
[tx, txInfo] = sixgr.phy.ul.PRACH_Tx(cfg);
[~, rxInfo] = sixgr.phy.ul.PRACH_Rx( ...
    tx.Waveform, cfg, "Carrier", tx.Carrier, "PRACH", tx.PRACH);
expectedSlots = mapped.TimingResolution.Occasions.AbsoluteSlot;
assert(isequal(txInfo.PRACHOccasion.TimingResolution.Occasions.AbsoluteSlot, ...
    expectedSlots), "PRACH transmitter used a different occasion resolver.");
assert(isequal(rxInfo.PRACHOccasion.TimingResolution.Occasions.AbsoluteSlot, ...
    expectedSlots), "PRACH receiver used a different occasion resolver.");

% An explicit NPRACHSlot must select and publish the same canonical
% occasion instead of bypassing the resolver. A later repetition proves
% that PRACH-slot and carrier-slot periods remain coupled exactly.
[~, explicitInfo] = sixgr.phy.ul.PRACH_Tx(cfg, ...
    "NPRACHSlot", mapped.PRACHSlotIndex0);
assert(~isempty(fieldnames(explicitInfo.PRACHOccasion)) && ...
    explicitInfo.ResolvedNPRACHSlot == mapped.PRACHSlotIndex0 && ...
    explicitInfo.PRACHOccasion.SlotIndex0 == mapped.SlotIndex0, ...
    "Explicit NPRACHSlot bypassed or disagreed with canonical mapping.");
nextPRACHSlot = mapped.PRACHSlotIndex0 + ...
    mapped.TimingResolution.PeriodPRACHSlots;
[~, repeatedInfo] = sixgr.phy.ul.PRACH_Tx(cfg, ...
    "NPRACHSlot", nextPRACHSlot);
assert(repeatedInfo.PRACHOccasion.PeriodIndex == 1 && ...
    repeatedInfo.PRACHOccasion.PRACHSlotIndex0 == nextPRACHSlot && ...
    repeatedInfo.PRACHOccasion.SlotIndex0 == mapped.SlotIndex0 + ...
        mapped.TimingResolution.PeriodCarrierSlots, ...
    "Explicit NPRACHSlot did not preserve canonical repetition timing.");
inactiveSlot = localFirstInactivePRACHSlot(mapped.TimingResolution);
localAssertError(@() sixgr.phy.ul.PRACH_Tx(cfg, ...
    "NPRACHSlot", inactiveSlot), ...
    "sixgr:rach:mapPRACHToOccasion:RequestedSlotInactive");

msg1 = sixgr.phy.ra.generateMsg1PRACHWaveform(cfg, ...
    struct("ScenarioName", "prach_shared_timing", ...
    "CarrierSCSkHz", 15, "NSizeGrid", 52, ...
    "PRACHConfigurationIndex", 16, "PRACHFormat", "0", ...
    "PRACHSubcarrierSpacing", 1.25, ...
    "RootSequenceIndex", 0, "PreambleIndex", 0, ...
    "ZeroCorrelationZoneConfig", 0, ...
    "RestrictedSetType", "UnrestrictedSet", ...
    "FrequencyStart", 0, "PRACHOccasionSlot", 1, "NCellID", 1));
assert(isfield(msg1, "Occasion") && ...
    isequal(msg1.Occasion.TimingResolution.Occasions.AbsoluteSlot, ...
    expectedSlots), ...
    "Random-access Msg1 scheduler did not use the canonical PRACH timing.");

ok = true;
end

function localVerifyEveryConfigurationTableRow()
tables = nrPRACHConfig.Tables;
contexts = { ...
    "FR1", "FDD", tables.ConfigurationsFR1PairedSUL, [1.25 5 15 30]; ...
    "FR1", "SUL", tables.ConfigurationsFR1PairedSUL, [1.25 5 15 30]; ...
    "FR1", "TDD", tables.ConfigurationsFR1Unpaired, [1.25 5 15 30]; ...
    "FR2", "TDD", tables.ConfigurationsFR2, [60 120 480 960]};
checked = 0;
for contextIndex = 1:size(contexts, 1)
    range = contexts{contextIndex, 1};
    duplex = contexts{contextIndex, 2};
    source = contexts{contextIndex, 3};
    candidateSCS = contexts{contextIndex, 4};
    for rowIndex = 1:height(source)
        index = double(source.ConfigurationIndex(rowIndex));
        expectedFormat = string(source.PreambleFormat{rowIndex});
        if expectedFormat == "-"
            continue;
        end
        prach = nrPRACHConfig;
        prach.FrequencyRange = range;
        prach.DuplexMode = duplex;
        prach.ConfigurationIndex = index;
        accepted = false;
        lastFailure = [];
        for scs = candidateSCS
            try
                prach.SubcarrierSpacing = scs;
                validateConfig(prach);
                accepted = true;
                break;
            catch cause
                lastFailure = cause;
            end
        end
        assert(accepted, ...
            "No supported PRACH SCS validated for %s/%s index %d: %s", ...
            range, duplex, index, localFailureMessage(lastFailure));
        allowedFormats = split(expectedFormat, "/");
        assert(any(string(prach.Format) == allowedFormats), ...
            "Toolbox format mismatch for %s/%s index %d.", ...
            range, duplex, index);
        assert(isfinite(double(prach.PRACHSlotsPerPeriod)) && ...
            double(prach.PRACHSlotsPerPeriod) >= 1, ...
            "Invalid exact repetition period for %s/%s index %d.", ...
            range, duplex, index);
        if range == "FR1"
            carrierSCS = 15;
            if scs >= 30
                carrierSCS = 30;
            end
            rangeSubtype = "FR1";
        else
            carrierSCS = 120;
            rangeSubtype = "FR2-1";
        end
        resolved = sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
            "FrequencyRange", rangeSubtype, "DuplexMode", duplex, ...
            "ConfigurationIndex", index, ...
            "CarrierSubcarrierSpacingKHz", carrierSCS, ...
            "NSizeGrid", 275, ...
            "PRACHSubcarrierSpacingKHz", scs, ...
            "SequenceIndex", 0, "PreambleIndex", 0, ...
            "RestrictedSet", "UnrestrictedSet", ...
            "ZeroCorrelationZone", 0, "Msg1FDM", 1);
        assert(resolved.ConfigurationIndex == index && ...
            resolved.TableRow.ConfigurationIndex == index && ...
            any(resolved.Format == allowedFormats) && ...
            resolved.TablePeriodFrames == double(source.x(rowIndex)) && ...
            ~isempty(resolved.Occasions), ...
            "Canonical resolver mismatch for %s/%s index %d.", ...
            range, duplex, index);
        assert(all(resolved.Occasions.StartSymbol >= 0) && ...
            all(resolved.Occasions.StartSymbol < 14), ...
            "Resolver returned an out-of-slot start symbol for %s/%s index %d.", ...
            range, duplex, index);
        localCompareFirstOccasionToToolbox( ...
            resolved, prach, carrierSCS, 275, range, duplex, index);
        checked = checked + 1;
    end
end
assert(checked == 1031, ...
    "Expected 1031 FR/duplex configuration-index rows, checked %d.", checked);
end

function localCompareFirstOccasionToToolbox( ...
        resolved, prach, carrierSCS, nSizeGrid, range, duplex, index)
row = resolved.Occasions(1, :);
carrier = nrCarrierConfig;
carrier.SubcarrierSpacing = carrierSCS;
carrier.NSizeGrid = nSizeGrid;
carrier.NFrame = row.Frame;
carrier.NSlot = row.SlotWithinFrame;
prach.NPRACHSlot = row.PRACHSlot;
prach.ActivePRACHSlot = row.ActivePRACHSlot;
prach.TimeIndex = row.TimeIndex;
prach.FrequencyIndex = row.FrequencyIndex;
[indices, info] = nrPRACHIndices(carrier, prach, ...
    "IndexStyle", "subscript", "IndexBase", "0based");
assert(~isempty(indices), ...
    "Direct nrPRACHIndices is empty at resolver slot for %s/%s index %d.", ...
    range, duplex, index);
symbols = unique(double(indices(:, 2))).';
assert(symbols(1) == row.StartSymbol, ...
    "Resolver/direct Toolbox start-symbol mismatch for %s/%s index %d.", ...
    range, duplex, index);
if double(prach.LRA) ~= 839
    assert(numel(symbols) == row.DurationSymbols && ...
        isequal(symbols, row.StartSymbol + (0:(row.DurationSymbols - 1))), ...
        "Resolver/direct Toolbox symbol-duration mismatch for %s/%s index %d.", ...
        range, duplex, index);
end
assert(isfield(info, "PRBSet") && ...
    min(double(info.PRBSet)) == row.FrequencyStart, ...
    "Resolver/direct Toolbox frequency-occasion mismatch for %s/%s index %d.", ...
    range, duplex, index);
end

function text = localFailureMessage(cause)
if isempty(cause)
    text = "no Toolbox error was captured";
else
    text = string(cause.message);
end
end

function result = localResolve(spec)
result = sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
    "FrequencyRange", spec.Range, ...
    "DuplexMode", spec.Duplex, ...
    "ConfigurationIndex", spec.Index, ...
    "CarrierSubcarrierSpacingKHz", spec.CarrierSCS, ...
    "NSizeGrid", spec.Grid, ...
    "PRACHSubcarrierSpacingKHz", spec.PRACHSCS, ...
    "SequenceIndex", 0, "PreambleIndex", 0, ...
    "RestrictedSet", "UnrestrictedSet", ...
    "ZeroCorrelationZone", 0, "Msg1FDM", 1);
end

