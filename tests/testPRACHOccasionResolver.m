function slot = localFirstInactivePRACHSlot(timing)
active = unique(double(timing.Occasions.PRACHSlot));
period = double(timing.PeriodPRACHSlots);
slot = find(~ismember(0:(period - 1), active), 1, "first") - 1;
assert(~isempty(slot), ...
    "Regression configuration unexpectedly activates every PRACH slot.");
end

function localAssertError(fcn, expectedID)
threw = false;
try
    fcn();
catch cause
    threw = true;
    assert(string(cause.identifier) == string(expectedID), ...
        "Expected error %s, got %s: %s", ...
        expectedID, cause.identifier, cause.message);
end
assert(threw, "Expected error %s was not thrown.", expectedID);
end
