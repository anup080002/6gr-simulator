    "ReceivedUEIdentity", "UE-1", ...
    "SRB1InstalledBeforeSetupComplete", false), ...
    "sixgr:phy:ia:InvalidRRCStateTransition");
end

function testBoundedRRCMessagesRoundTrip(testCase)
msg3 = sixgr.mac.ra.buildMsg3Payload( ...
    "UEId", 7, "UEIdentity", "UE-7", ...
    "RRCSetupRequest", true);
decoded3 = sixgr.mac.ra.parseMsg3Payload(msg3.PayloadBits);
verifyTrue(testCase, decoded3.RRCSetupRequestPresent);
verifyEqual(testCase, decoded3.RRCSetupRequest.UEIdentity, "UE-7");
verifyEqual(testCase, decoded3.RRCSetupRequestSHA256, ...
    msg3.RRCSetupRequestSHA256);

msg4 = sixgr.mac.ra.buildMsg4ContentionResolution( ...
    decoded3.ContentionIdentity, ...
    "FinalCRNTI", 4660, "RRCSetup", true, ...
    "TransactionID", 2, "SRB1LCID", 1);
decoded4 = sixgr.mac.ra.parseMsg4ContentionResolution( ...
    msg4.PayloadBits);
verifyTrue(testCase, decoded4.RRCSetupPresent);
verifyEqual(testCase, decoded4.RRCSetup.TransactionID, 2);
verifyEqual(testCase, decoded4.RRCSetup.SRB1LCID, 1);

complete = sixgr.mac.ra.buildRRCSetupComplete( ...
    "TransactionID", 2, "SRB1LCID", 1, ...
    "UEIdentity", "UE-7");
decodedComplete = sixgr.mac.ra.parseRRCSetupComplete( ...
    complete.PayloadBits);
verifyEqual(testCase, decodedComplete.TransactionID, 2);
verifyEqual(testCase, decodedComplete.SRB1LCID, 1);
verifyEqual(testCase, decodedComplete.UEIdentity, "UE-7");
verifyEqual(testCase, decodedComplete.PayloadHash, ...
    complete.PayloadHash);
end

function value = localBool(token)
if islogical(token)
    value = token;
else
    value = lower(strtrim(string(token))) == "true";
end
end
