function testRRCSetupTransitions(testCase)
root = fullfile(fileparts(mfilename("fullpath")), ...
    "vectors", "initial_access");
inputPath = fullfile(root, "rrc_setup_transition_test_vectors.csv");
inputOptions = delimitedTextImportOptions( ...
    "NumVariables", 8, "Delimiter", ",", "DataLines", [2 Inf], ...
    "VariableNames", ["CaseID","SequenceName","EventSequence", ...
    "ExpectedTransactionID","ReceivedTransactionID","UEIdentity", ...
    "ReceivedUEIdentity","SRB1InstalledBeforeSetupComplete"], ...
    "VariableTypes", ["string","string","string","double","double", ...
    "string","string","string"]);
input = readtable(inputPath, inputOptions);
expectedPath = fullfile(root, "expected_rrc_setup_transition.csv");
expectedOptions = delimitedTextImportOptions( ...
    "NumVariables", 7, "Delimiter", ",", "DataLines", [2 Inf], ...
    "VariableNames", ["CaseID","ExpectedFinalUEState", ...
    "ExpectedFinalGNBState","ExpectedRRCConnected","ExpectedError", ...
    "ExpectedStateMutationAfterFailure","ExpectedStatus"], ...
    "VariableTypes", repmat("string", 1, 7));
expected = readtable(expectedPath, expectedOptions);
verifyEqual(testCase, height(input), 32);
verifyEqual(testCase, input.CaseID, expected.CaseID);
for ii = 1:height(input)
    actual = sixgr.phy.ia. ...
        RRCConnectionEstablishmentStateMachine.evaluate( ...
        "CaseID", input.CaseID(ii), ...
        "EventSequence", input.EventSequence(ii), ...
        "ExpectedTransactionID", ...
            double(input.ExpectedTransactionID(ii)), ...
        "ReceivedTransactionID", ...
            double(input.ReceivedTransactionID(ii)), ...
        "UEIdentity", input.UEIdentity(ii), ...
        "ReceivedUEIdentity", input.ReceivedUEIdentity(ii), ...
        "SRB1InstalledBeforeSetupComplete", ...
            localBool(input.SRB1InstalledBeforeSetupComplete(ii)));
    verifyEqual(testCase, actual.FinalUEState, ...
        expected.ExpectedFinalUEState(ii));
    verifyEqual(testCase, actual.FinalGNBState, ...
        expected.ExpectedFinalGNBState(ii));
    verifyEqual(testCase, actual.RRCConnected, ...
        localBool(expected.ExpectedRRCConnected(ii)));
    expectedError = string(expected.ExpectedError(ii));
    if ismissing(expectedError)
        expectedError = "";
    end
    verifyEqual(testCase, actual.ErrorIdentifier, expectedError);
    verifyEqual(testCase, actual.StateMutationAfterFailure, ...
        localBool(expected.ExpectedStateMutationAfterFailure(ii)));
    verifyFalse(testCase, actual.ProxyUsed);
    verifyFalse(testCase, actual.FallbackUsed);
end
end

