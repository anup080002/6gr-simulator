verifyError(testCase, @() sixgr.phy.ia. ...
    RRCConnectionEstablishmentStateMachine.execute( ...
    "EventSequence", "CELL_SELECTED|RRC_SETUP_COMPLETE_OK", ...
    "ExpectedTransactionID", 0, ...
