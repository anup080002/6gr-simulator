function ok=testPUCCHReceiverOnlyExportEvidence()
% Metadata-only export regression, not a physical detection qualification.
% Mirrors the schema of a scheduled gNB observation without a UE producer.
setup6GRSimToolkit('Verbose',false,'RunToolboxChecks',false);
T=table([24;29],repmat("UL",2,1),true(2,1),false(2,1), ...
    [true;false],[true;false],[false;true],["10110110100";""], ...
    zeros(2,1),ones(2,1),10*ones(2,1),zeros(2,1), ...
    [199.118628;199.118628],repmat("resource_grid_pre_equalization",2,1), ...
    repmat("metadata_fixture_no_physical_qualification",2,1), ...
    'VariableNames',{'Slot','Direction','ReceiverOnlyAssignment', ...
    'PUCCHTransmissionPrepared','PUCCHDecodeOk','ReceiverUsable','DTXFlag', ...
    'UCIDecodedBitVector','ReceiverExpectedHARQBitCount','ReceiverExpectedSRBitCount', ...
    'ReceiverExpectedCSIPart1BitCount','ReceiverExpectedCSIPart2BitCount', ...
    'NoiseVariance','NoiseVarianceDomain','EvidenceClass'});
original=T;
out=sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("PUCCH",T);
assert(isequal(out.ReceiverUsable,original.ReceiverUsable), ...
    'test:PUCCHReceiverEvidenceOverwritten', ...
    'Export acceptance must not overwrite the independently executed receiver usability flag.');
assert(isequal(out.PUCCHDecodeOk,original.PUCCHDecodeOk) && ...
    isequal(out.DecodeSuccess,original.PUCCHDecodeOk), ...
    'test:PUCCHReceiverDecodeEvidenceOverwritten', ...
    'An independent decoded outcome must not be inferred from absent transmitter/CRC reference fields.');
assert(all(out.ReceiverOnlyAssignment) && all(~out.PUCCHTransmissionPrepared));
assert(string(out.UCIDecodedBitVector(1))==original.UCIDecodedBitVector(1));
assert(all(~out.StrictReceiverEvidenceOk), ...
    'Incomplete export-stage proof must remain incomplete, not be promoted into strict qualification.');
assert(~any(out.SuccessFlag), ...
    'A decoded receiver-only detection is not a successful transmitted PUCCH.');
assert(~ismember('UCIExpectedBitVector',out.Properties.VariableNames) || ...
    all(~matches(string(out.UCIExpectedBitVector),regexpPattern('^[01]+$'))), ...
    'Receiver-only annotation must not invent transmitted reference bits.');
assert(isequaln(T,original),'Canonicalization must not modify its caller-owned input.');
again=sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("PUCCH",out);
changed=strings(0,1);
for name=string(out.Properties.VariableNames)
    if ~isequaln(again.(name),out.(name)), changed(end+1,1)=name; end %#ok<AGROW>
end
assert(isequaln(again,out),'Repeated publication changed columns: %s',strjoin(changed,', '));
% A finite SINR does not turn a rejected receiver result into a usable one.
rejected=T(2,:); rejected.ReceiverHestSINR_dB=20;
rejectedOut=sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("PUCCH",rejected);
assert(~rejectedOut.ReceiverUsable && ~rejectedOut.DecodeSuccess);
% An unavailable label must never protect a finite proxy from quarantine.
proxy=out(1,:); proxy.DecoderTruthProxySINR_dB=20;
proxyOut=sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("PUCCH",proxy);
assert(isnan(proxyOut.DecoderTruthProxySINR_dB) && ...
    proxyOut.DecoderTruthProxySINRSource=="evm_proxy_quarantined_not_decoder_truth");
% Transmitted but wrongly decoded content must remain a scoring failure,
% even if the practical receiver accepted its own hypothesis.
wrong=T(1,:); wrong.ReceiverOnlyAssignment=false;
wrong.PUCCHTransmissionPrepared=true; wrong.Status="FAIL";
wrong.UCIContentMatch=false; wrong.FalseAck=true;
wrongOut=sixgr.truth.CoupledTruthRuntime.canonicalizePersistedControlReferenceTable("PUCCH",wrong);
assert(wrongOut.ReceiverUsable && wrongOut.DecodeSuccess && ...
    ~wrongOut.SuccessFlag && wrongOut.FailureFlag && wrongOut.Status=="FAIL");
fprintf('PUCCH_RECEIVER_ONLY_EXPORT_PASS raw_flags_preserved=1 no_invented_TX_success=1 RF_executions=0\n');
ok=true;
end
