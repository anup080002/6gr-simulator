function ok = testOFDMSamplingResolver()
%TESTOFDMSAMPLINGRESOLVER Validate Toolbox-derived OFDM sampling and windowing.

setup6GRSimToolkit("Verbose", false);

vectors = readtable(localVectorPath("frame_carrier_grid_test_vectors.csv"), ...
    "TextType", "string");
valid = false(height(vectors), 1);
for i = 1:height(vectors)
    valid(i) = localTruth(vectors.ExpectedValid(i));
end
vectors = vectors(valid, :);
assert(height(vectors) == 56, ...
    "All 56 valid carrier-table cells must enter the OFDM round-trip test.");

for i = 1:height(vectors)
    testID = string(vectors.TestID(i));
    gridState = sixgr.phy.frame.CarrierGridConfig.resolve( ...
        "Role", vectors.Role(i), ...
        "FrequencyRange", vectors.FrequencyRange(i), ...
        "CenterFrequencyHz", ...
            double(vectors.RepresentativeCenterFrequency_Hz(i)), ...
        "ChannelBandwidthMHz", double(vectors.ChannelBandwidth_MHz(i)), ...
        "SubcarrierSpacingKHz", double(vectors.CarrierSCS_kHz(i)));
    carrier = localCarrier(gridState);

    resolved = sixgr.phy.frame.OFDMSamplingResolver.resolve(gridState);
    directInfo = nrOFDMInfo(carrier);
    assert(resolved.Nfft == double(directInfo.Nfft), ...
        "Vector %s Nfft differs from nrOFDMInfo.", testID);
    assert(resolved.SampleRateHz == double(directInfo.SampleRate), ...
        "Vector %s sample rate differs from nrOFDMInfo.", testID);
    assert(isequal(resolved.CyclicPrefixLengths, ...
        double(directInfo.CyclicPrefixLengths(:).')), ...
        "Vector %s CP lengths differ from nrOFDMInfo.", testID);
    assert(resolved.Nfft >= 12 * carrier.NSizeGrid, ...
        "Vector %s aliases occupied subcarriers.", testID);
    assert(resolved.SampleRateHz == resolved.Nfft * ...
        carrier.SubcarrierSpacing * 1e3, ...
        "Vector %s violates Fs=Nfft*SCS.", testID);
    assert(resolved.WindowingSamples == 0 && ...
        double(resolved.ToolboxOFDMInfo.Windowing) == 0 && ...
        string(resolved.Source) == "nrOFDMInfo", ...
        "Vector %s must use Toolbox defaults with explicit zero windowing.", testID);

    txGrid = localDeterministicGrid( ...
        12 * carrier.NSizeGrid, resolved.SymbolsPerSlot, i);
    [txWaveform, txInfo] = nrOFDMModulate( ...
        carrier, txGrid, ...
        "Nfft", resolved.Nfft, ...
        "SampleRate", resolved.SampleRateHz, ...
        "Windowing", 0);
    rxGrid = nrOFDMDemodulate( ...
        carrier, txWaveform, ...
        "Nfft", resolved.Nfft, ...
        "SampleRate", resolved.SampleRateHz);
    assert(isequal(size(rxGrid), size(txGrid)), ...
        "Vector %s OFDM round-trip dimensions changed.", testID);
    delta = rxGrid - txGrid;
    nmse = sum(abs(delta(:)).^2) / sum(abs(txGrid(:)).^2);
    evmPercent = 100 * sqrt(nmse);
    assert(nmse <= 1e-12, ...
        "Vector %s OFDM round-trip NMSE %.15g exceeds 1e-12.", ...
        testID, nmse);
    assert(evmPercent <= 1e-4, ...
        "Vector %s OFDM round-trip EVM %.15g%% exceeds 1e-4%%.", ...
        testID, evmPercent);
    assert(size(txWaveform, 1) == ...
        sum(double(txInfo.SymbolLengths(1:resolved.SymbolsPerSlot))), ...
        "Vector %s waveform sample count differs from nrOFDMModulate info.", ...
        testID);
end

extendedState = sixgr.phy.frame.CarrierGridConfig.resolve( ...
    "Role", "gNB", "FrequencyRange", "FR1", ...
    "ChannelBandwidthMHz", 20, "SubcarrierSpacingKHz", 60, ...
    "CyclicPrefix", "extended");
extendedCarrier = localCarrier(extendedState);
extendedOFDM = sixgr.phy.frame.OFDMSamplingResolver.resolve(extendedCarrier);
assert(extendedOFDM.SymbolsPerSlot == 12 && ...
    numel(extendedOFDM.CyclicPrefixLengths) == 48, ...
    "60 kHz extended CP must resolve 12 symbols/slot across four slots/subframe.");
extendedGrid = localDeterministicGrid( ...
    12 * extendedCarrier.NSizeGrid, extendedOFDM.SymbolsPerSlot, 6002);
extendedWaveform = nrOFDMModulate( ...
    extendedCarrier, extendedGrid, ...
    "Nfft", extendedOFDM.Nfft, ...
    "SampleRate", extendedOFDM.SampleRateHz, ...
    "Windowing", 0);
extendedRecovered = nrOFDMDemodulate( ...
    extendedCarrier, extendedWaveform, ...
    "Nfft", extendedOFDM.Nfft, ...
    "SampleRate", extendedOFDM.SampleRateHz);
extendedNMSE = sum(abs(extendedRecovered(:) - extendedGrid(:)).^2) / ...
    sum(abs(extendedGrid(:)).^2);
assert(extendedNMSE <= 1e-12, ...
    "Extended-CP OFDM round-trip NMSE %.15g exceeds 1e-12.", extendedNMSE);

referenceGrid = sixgr.phy.frame.CarrierGridConfig.resolve( ...
    "Role", "gNB", "FrequencyRange", "FR1", ...
    "ChannelBandwidthMHz", 20, "SubcarrierSpacingKHz", 30);
referenceCarrier = localCarrier(referenceGrid);
referenceOFDM = sixgr.phy.frame.OFDMSamplingResolver.resolve(referenceCarrier);
explicitOFDM = sixgr.phy.frame.OFDMSamplingResolver.resolve( ...
    referenceCarrier, ...
    "Nfft", referenceOFDM.Nfft, ...
    "SampleRate", referenceOFDM.SampleRateHz, ...
    "WindowingSamples", 0);
assert(string(explicitOFDM.Source) == "explicit_validated" && ...
    explicitOFDM.Nfft == referenceOFDM.Nfft && ...
    explicitOFDM.SampleRateHz == referenceOFDM.SampleRateHz, ...
    "An explicit accepted Nfft/sample-rate pair must be labeled explicit_validated.");
referenceSymbols = localDeterministicGrid( ...
    12 * referenceCarrier.NSizeGrid, referenceOFDM.SymbolsPerSlot, 7001);

[omittedSamples, omittedInfo] = ...
    sixgr.phy.waveform.resolveOFDMWindowing(struct(), referenceCarrier);
explicitZeroCfg = sixgr.util.structSet( ...
    struct(), "phy.ofdm.windowingSamples", 0);
[zeroSamples, zeroInfo] = sixgr.phy.waveform.resolveOFDMWindowing( ...
    explicitZeroCfg, referenceCarrier);
assert(omittedSamples == 0 && zeroSamples == 0 && ...
    ~omittedInfo.OFDMWindowingEnabled && ~zeroInfo.OFDMWindowingEnabled, ...
    "Omitted and explicitly zero windowing must both resolve to zero samples.");
omittedWaveform = nrOFDMModulate( ...
    referenceCarrier, referenceSymbols, "Windowing", omittedSamples);
zeroWaveform = nrOFDMModulate( ...
    referenceCarrier, referenceSymbols, "Windowing", zeroSamples);
directNoWindowing = nrOFDMModulate( ...
    referenceCarrier, referenceSymbols, "Windowing", 0);
assert(isequal(omittedWaveform, zeroWaveform) && ...
    isequal(omittedWaveform, directNoWindowing), ...
    "Omitted simulator windowing must match explicit zero and direct no-windowing samples.");

nonzeroCfg = sixgr.util.structSet( ...
    struct(), "phy.ofdm.windowingSamples", 1);
[nonzeroSamples, nonzeroInfo] = ...
    sixgr.phy.waveform.resolveOFDMWindowing(nonzeroCfg, referenceCarrier);
nonzeroWaveform = nrOFDMModulate( ...
    referenceCarrier, referenceSymbols, "Windowing", nonzeroSamples);
assert(nonzeroSamples == 1 && nonzeroInfo.OFDMWindowingEnabled && ...
    string(nonzeroInfo.OFDMWindowingValidation.ValidatedBy) == ...
        "nrOFDMModulate", ...
    "An explicit valid nonzero sample count must be applied exactly.");
assert(size(nonzeroWaveform, 1) == size(directNoWindowing, 1), ...
    "Explicit windowing must not unexpectedly alter frame length.");

assertThrows(@() sixgr.phy.waveform.resolveOFDMWindowing( ...
    sixgr.util.structSet(struct(), "phy.ofdm.windowingSamples", -1), ...
    referenceCarrier), ...
    "sixgr:phy:frame:InvalidWindowingSamples");
assertThrows(@() sixgr.phy.waveform.resolveOFDMWindowing( ...
    sixgr.util.structSet(struct(), "phy.ofdm.windowingSamples", 1.5), ...
    referenceCarrier), ...
    "sixgr:phy:frame:InvalidWindowingSamples");
assertThrows(@() sixgr.phy.waveform.resolveOFDMWindowing( ...
    sixgr.util.structSet(struct(), "phy.ofdm.windowingSamples", ...
        referenceOFDM.Nfft + 1), ...
    referenceCarrier), ...
    "sixgr:phy:frame:InvalidOFDMSamplingConfiguration");
assertThrows(@() sixgr.phy.frame.OFDMSamplingResolver.resolve( ...
    referenceCarrier, "Nfft", 12 * referenceCarrier.NSizeGrid - 1), ...
    "sixgr:phy:frame:OFDMAliasing");

ok = true;
end

function carrier = localCarrier(state)
carrier = nrCarrierConfig;
carrier.NCellID = 1;
carrier.NSizeGrid = state.NSizeGrid;
carrier.NStartGrid = state.NStartGrid;
carrier.SubcarrierSpacing = state.SubcarrierSpacingKHz;
carrier.CyclicPrefix = string(state.CyclicPrefix);
carrier.NSlot = 0;
carrier.NFrame = 0;
end

function grid = localDeterministicGrid(subcarriers, symbols, seed)
grid = complex(zeros(subcarriers, symbols));
locations = unique([ ...
    1, ...
    subcarriers, ...
    max(1, floor(subcarriers / 4)), ...
    max(1, floor(subcarriers / 2)), ...
    max(1, floor(3 * subcarriers / 4))]);
for i = 1:numel(locations)
    for symbol = 1:symbols
        phaseIndex = mod(seed + 17 * locations(i) + 29 * symbol, 16);
        grid(locations(i), symbol) = exp(1j * 2 * pi * phaseIndex / 16);
    end
end
end

function tf = localTruth(value)
if islogical(value)
    tf = logical(value);
elseif isnumeric(value)
    tf = logical(value ~= 0);
else
    tf = any(strcmpi(strtrim(string(value)), ["true", "1", "yes"]));
end
end

function assertThrows(fn, expectedID)
try
    fn();
catch ME
    assert(strcmp(ME.identifier, expectedID), ...
        "Expected error %s, received %s (%s).", ...
        expectedID, ME.identifier, ME.message);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.", expectedID);
end

function path = localVectorPath(name)
testDirectory = fileparts(mfilename("fullpath"));
path = fullfile(testDirectory, "vectors", "frame_grid", name);
assert(isfile(path), "Mandatory frame/grid vector is missing: %s", path);
end
