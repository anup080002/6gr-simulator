function ok = testPDSCHBLERStopPolicy()
%TESTPDSCHBLERSTOPPOLICY Exercise real HARQ and canonical bounded stopping.

setup6GRSimToolkit("Verbose",false,"RunToolboxChecks",false);
vectorRoot = fullfile(fileparts(mfilename("fullpath")),"vectors","pdsch");
evidence = sixgr.pdsch.PDSCHCoverageExecutor.run( ...
    "VectorRoot",vectorRoot,"SeedList",[11 23 47 89], ...
    "RunDeclaredCoverage",false,"RunPairwise",false, ...
    "RunNoNoise",false,"RunBLER",true, ...
    "BLERCampaignIDs","BLER-AWGN-HARQ-0231", ...
    "BLEROperatingPointLimit",1, ...
    "BLERMinimumTrials",2,"BLERMaximumTrials",4, ...
    "BLERMinimumErrors",1,"BLERCIHalfWidthTarget",0.49, ...
    "Strict",true);

curve = evidence.BLERCurve;
assert(height(curve) == 1 && curve.Status == "PASS", ...
    "Bounded HARQ BLER smoke must produce one complete passing point.");
assert(curve.Trials == 4 && curve.TBErrors == 0, ...
    "Deterministic HARQ RV 0/2/3/1 smoke changed unexpectedly.");
assert(curve.MinErrorsRequired == 1, ...
    "Configured BLER minimum-error target was not preserved.");
assert(curve.StopReason == "FIXED_TRIAL_BUDGET_COMPLETE", ...
    ["An error-free fixed-budget point must not be mislabeled as a " ...
    "one-sided censored confidence bound."]);
assert(curve.CILower <= curve.BLER && curve.BLER <= curve.CIUpper ...
    && isfinite(curve.CIHalfWidth), ...
    "Wilson confidence bounds must be finite and enclose observed BLER.");
assert(~contains(curve.StopReason,"INCOMPLETE"), ...
    "A required BLER operating point remained incomplete.");

fprintf("PDSCH BLER stop policy: %d/%d errors, %s\n", ...
    curve.TBErrors,curve.Trials,curve.StopReason);
ok = true;
end
