function ok=testH4100ImpairedCSIReception()
% Full-band H4 CSI-RS through actual 64x4 CDL and TX/RX RF streams.
% One bounded receiver component, NOT access, physical UCI, or BLER acceptance.
% CSI wire decoding below is serialization only, not a PUCCH receiver claim.
setup6GRSimToolkit('Verbose',false);
source=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_gate.yaml');
folder=fullfile(pwd,'results','lls','h4_impaired_csi', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(folder);
cfg=sixgr.lls6g.buildInternalConfig(source,folder);
cfg=sixgr.truth.attachFixedLinkRuntimeAntennaContext(cfg,1,1);
cfg=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,6);
cfg.lls6g.userContext.RuntimeCurrentSlot=6;
cfg.runtime.currentSlot=6;
cfg.lls6g.runtimePowerContext=struct( ...
    'WaveformAmplitudeUnit','normalized_unit_es','PhysicalDevicePowerClaim',false);
carrier=sixgr.phy.grid.makeCarrier(cfg);
assert(carrier.NSizeGrid==273 && carrier.SubcarrierSpacing==30 && ...
    cfg.phy.fc_Hz==4e9 && cfg.phy.nTxAnt==64 && cfg.phy.nRxAnt==4);
assert(sixgr.mimo.resolveRankPolicy(cfg).AdaptiveRank && ...
    isequal(cfg.phy.csi.reportConfiguration.AllowedRanks,[1 2 4]));
physical=sixgr.phy.refsig.materializeCSIRSPhysicalGrid( ...
    carrier,cfg,'WaveformPortCount',64);
assert(physical.Event.Transmitted && physical.Event.NumResources==8);
[waveform,ofdm]=nrOFDMModulate(carrier,physical.Grid);
assert(ofdm.SampleRate==122.88e6 && ofdm.Nfft==4096);
margin=256;
waveform=[waveform;zeros(margin,64)];
firstSample=sixgr.phy.frame.slotStartSample(carrier,5,ofdm.SampleRate);
epoch=cfg.rf.configurationEpoch;
txStream=sixgr.rf.runtime.RFImpairmentStream( ...
    cfg,'tx','DL',ofdm.SampleRate,64,firstSample,epoch,false);
tx=txStream.apply(sixgr.phy.waveform.WaveformChunk(waveform,firstSample),epoch);
assert(tx.Replay.DACQuantizationApplied && tx.Replay.PAApplied && ...
    tx.Replay.PhaseNoiseApplied);
user=cfg.lls6g.userContext;
channel=sixgr.channel.ChannelFactory.createRuntimeChannelState(cfg,'DL', ...
    'UEIndex',1,'ServingCell',1,'Seed',5101331,'AbsoluteSampleIndex',firstSample);
channel=sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    channel,cfg,tx.Waveform,struct('OFDM',ofdm), ...
    'NumTxAnt',64,'NumRxAnt',4, ...
    'TransmitAntennaRuntime',user.RuntimeServingBSAntenna, ...
    'ReceiveAntennaRuntime',user.RuntimeUEAntenna, ...
    'TransmitAntennaMeta',user.RuntimeServingBSAntennaMeta, ...
    'ReceiveAntennaMeta',user.RuntimeUEAntennaMeta);
[propagated,replay]=sixgr.channel.ChannelFactory.applyRuntimeChannelState( ...
    channel,tx.Waveform,'OutputSampleAlignment','continuous_raw_samples');
assert(replay.ChannelFadingApplied && size(propagated,2)==4 && ...
    replay.RuntimeChannelAngleEvidenceAvailable);
[antennaCapture,noise]=sixgr.phy.waveform.addOccupiedREAWGN( ...
    propagated,carrier,cfg.channel.snr_dB,'Seed',5101332, ...
    'SignalEnergyPerOccupiedRE',sixgr.link.resolveAWGNReferenceEnergy(cfg));
rxStream=sixgr.rf.runtime.RFImpairmentStream( ...
    cfg,'rx','DL',ofdm.SampleRate,4,firstSample,epoch,false);
frontend=rxStream.apply( ...
    sixgr.phy.waveform.WaveformChunk(antennaCapture,firstSample),epoch);
assert(frontend.Replay.ADCQuantizationApplied && ...
    frontend.Replay.PhaseNoiseApplied && frontend.Replay.TimingOffsetApplied);
% Retain real receiver input before calling RX; no transmitter bits, known
% timing, channel coefficients or injected CFO are passed as its estimate.
save(fullfile(folder,'input.mat'),'cfg','carrier','ofdm','antennaCapture', ...
    'frontend','replay','noise','margin','-v7.3');
fprintf('H4_IMPAIRED_CSI_RX_START root=%s\n',folder);
rx=sixgr.phy.refsig.receiveCSIRSWaveform(carrier,cfg,frontend.Waveform, ...
    antennaCapture,[0 margin],struct());
[report,detail]=sixgr.phy.refsig.computeCSIRSFeedback(carrier,cfg,rx);
wire=sixgr.phy.mimo.CSIReportConfiguration( ...
    cfg.phy.csi.reportConfiguration,cfg.phy.csi.reportConfiguration.Epoch);
decoded=wire.decode(report.CSIPart1Bits,report.CSIPart2Bits);
assert(ismember(report.RI,[1 2 4]) && report.CRI>=0 && report.CRI<8 && ...
    decoded.RI==report.RI && decoded.PMI==report.PMI && ...
    decoded.CRI==report.CRI && decoded.CQI_CW0==report.CQI);
assert(~report.ConfiguredOracleUsed && ~rx.ReceiveTiming.OracleTimingUsed && ...
    ~detail.PDSCHDecodeAttempted && ~detail.DCIConsumed && ...
    rx.ReceiverTrackingCorrection.CFOEstimateAvailable);
assert(all(isfinite(rx.CSIRSChannelEstimate),'all') && ...
    all(isfinite(report.SelectionInfo.SelectedSINRPerRELayer),'all'));
row=table(4e9,100,273,30,ofdm.SampleRate,64,4,8,cfg.channel.snr_dB, ...
    report.RI,report.PMI,report.CRI,report.CQI,report.SINR_dB, ...
    rx.ReceiveTiming.TimingOffsetSamples, ...
    rx.ReceiverTrackingCorrection.EstimatedCFO_Hz, ...
    "CDL_RF_CSI_component_UCI_serialization_only_not_full_scenario",false, ...
    'VariableNames',{'CarrierHz','BandwidthMHz','NSizeGrid','SCS_kHz', ...
    'SampleRateHz','TxDimensions','RxDimensions','CSIResources', ...
    'ConfiguredSNR_dB','RI','PMI','CRI','CQI','MeasuredCSIObjective_dB', ...
    'TimingEstimateSamples','EstimatedCFO_Hz','Scope','ScenarioAccepted'});
writetable(row,fullfile(folder,'received_csi.csv'));
save(fullfile(folder,'output.mat'),'rx','report','decoded','detail','row','-v7.3');
fprintf('H4_IMPAIRED_CSI_PASS RI=%g PMI=%g CRI=%g CQI=%g CFO=%g evidence=%s\n', ...
    report.RI,report.PMI,report.CRI,report.CQI,row.EstimatedCFO_Hz,folder);
ok=true;
end
