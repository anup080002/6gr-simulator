function out = runPhase19RepairVerticalSlice(outputRoot, runTag)
%RUNPHASE19REPAIRVERTICALSLICE Execute the bounded coupled-truth repair gate.

if nargin < 1 || strlength(string(outputRoot)) == 0
    % runSingle owns the canonical <results>/lls/<scenario>/<run> layout.
    % Do not advertise an artifacts/ root that resolveResultsRoot must
    % reject and silently redirect.
    outputRoot = fullfile(pwd, "results");
end
outputRoot = char(string(outputRoot));
if nargin < 2 || strlength(string(runTag)) == 0
    runTag = "phase19_repair_vertical_slice";
end
runTag = char(string(runTag));

scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    pwd, "simulator", "configs", "scenarios", ...
    "webgui_sinr_sweep_64x4_mu_mimo_repair_slice.yaml"));
scenarioPath = string(scenario.ConfigPath);
out = sixgr.lls6g.runners.runSingle(scenarioPath, outputRoot, runTag);
link = sixgr.util.structGet(out.Result, "Link", struct());
rawTrials = sixgr.util.structGet(link, "RawTrials", struct());
dl = sixgr.util.structGet(rawTrials, "DL", table());
ul = sixgr.util.structGet(rawTrials, "UL", table());
fprintf("VERTICAL ok=%d dl=%d ul=%d\n", out.Ok, height(dl), height(ul));
assert(height(dl) >= 2 && height(ul) >= 2, ...
    "The coupled truth gate requires at least two real DL and UL trials.");
assert(all(dl.Layers == 2) && all(ul.Layers == 2), ...
    "Every vertical-slice PDSCH/PUSCH waveform must execute two layers.");
assert(all(dl.TxWaveformColumns == 64) && ...
    all(dl.PhysicalTxAntennas == 64), ...
    "DL must transmit on all 64 configured gNB elements.");
assert(all(ul.TxWaveformColumns == 4) && ...
    all(ul.RxWaveformBranches == 64), ...
    "UL must transmit on four UE elements and reach 64 gNB branches.");
assert(all(dl.HybridElementDomainApplied) && ...
    all(ul.HybridElementDomainApplied), ...
    "Hybrid element-domain precoding must be physically applied.");
assert(all(strcmpi(string(dl.TxWaveformDomain), "element")) && ...
    all(strcmpi(string(ul.TxWaveformDomain), "element")), ...
    "Both links must disclose an element-domain waveform.");
assert(all(isfinite(dl.PostEqSINR_dB)) && ...
    all(dl.PostEqSINR_dB > -60), ...
    "DL post-equalization SINR must be finite and physically plausible.");
for direction = ["DL","UL"]
    T = rawTrials.(direction);
    muRows = T(logical(T.MUMIMOEnabled) & double(T.MUMIMOGroupSize) >= 2, :);
    assert(height(muRows) >= 2 && ...
        any(string(muRows.MUMIMOPairingStatus) == "paired_shared_prb_spatial_multiplexing") && ...
        all(ismember(string(muRows.MUMIMOPairingMetricSource), ...
        ["measured_tdd_srs_reciprocal_complete_peer_subspace_hybrid_block_diagonalized_precoder_leakage", ...
         "measured_srs_complete_peer_subspace_irc_receive_projection_leakage"])) && ...
        all(isfinite(double(muRows.MUMIMOPairingMetricValue_dB))) && ...
        all(ismember(string(muRows.MUMIMOPairingEvidenceSource), ...
        ["causal_measured_srs_complete_peer_subspace_reciprocity_phase_only_hybrid_and_frozen_baseband", ...
         "causal_measured_srs_complete_peer_subspace_and_runtime_irc_covariance"])) && ...
        all(string(muRows.InterferenceMode) == "shared_slot_waveform_superposition") && ...
        all(double(muRows.InterferenceContributorCount) >= 1), ...
        "%s must contain a causally measured shared-waveform MU-MIMO group.", direction);
end

fprintf("DL posteq range=[%.4f %.4f], measured range=[%.4f %.4f]\n", ...
    min(dl.PostEqSINR_dB), max(dl.PostEqSINR_dB), ...
    min(dl.MeasuredSINR_dB), max(dl.MeasuredSINR_dB));
fprintf("UL posteq range=[%.4f %.4f], measured range=[%.4f %.4f]\n", ...
    min(ul.PostEqSINR_dB), max(ul.PostEqSINR_dB), ...
    min(ul.MeasuredSINR_dB), max(ul.MeasuredSINR_dB));
end
