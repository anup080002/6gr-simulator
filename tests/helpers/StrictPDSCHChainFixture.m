classdef StrictPDSCHChainFixture
    %STRICTPDSCHCHAINFIXTURE Test-only explicit PDSCH TX/RX fixture.

    methods (Static)
        function fixture = create(rankValue, varargin)
            ip = inputParser;
            ip.addParameter("NPRB", 1);
            ip.addParameter("FrequencySelective", false);
            ip.addParameter("UsePTRS", false);
            ip.addParameter("RNTI", 4660);
            ip.addParameter("NID", 42);
            ip.addParameter("TransportBlockSize", 40);
            ip.parse(varargin{:});
            opt = ip.Results;

            rankValue = double(rankValue);
            assert(isscalar(rankValue) && rankValue >= 1 ...
                && rankValue <= 8 && rankValue == fix(rankValue));
            if rankValue <= 4
                layerCount = rankValue;
            else
                splits = {[2 3],[3 3],[3 4],[4 4]};
                layerCount = splits{rankValue - 4};
            end
            numCodewords = numel(layerCount);
            nPRB = double(opt.NPRB);

            carrier = nrCarrierConfig;
            carrier.NCellID = double(opt.NID);
            carrier.NSizeGrid = nPRB;
            carrier.NStartGrid = 0;
            carrier.SubcarrierSpacing = 30;
            carrier.CyclicPrefix = "normal";
            carrier.NSlot = 0;
            carrier.NFrame = 0;
            K = nPRB * 12;
            L = carrier.SymbolsPerSlot;
            allocation = 0:(K*L - 1);
            if logical(opt.UsePTRS)
                ptrsPortSet = 0;
                ptrsConfigId = "PTRS-STRICT-FIXTURE";
            else
                ptrsPortSet = zeros(1,0);
                ptrsConfigId = "";
            end

            request = struct( ...
                "UEId",1, "RNTI",double(opt.RNTI), "RNTIType","C-RNTI", ...
                "ServingCellId",1, "SchedulingCellId",1, "CCId",0, ...
                "BWPId",0, "ConfigurationEpoch",1, ...
                "PRBSetBWPRelative",0:nPRB-1, ...
                "PRBSetCarrierRelative",0:nPRB-1, ...
                "SymbolAllocation",[0 L], "MappingType","A", ...
                "MCSTablePerCodeword",repmat("qam64",1,numCodewords), ...
                "MCSIndexPerCodeword",4*ones(1,numCodewords), ...
                "ModulationPerCodeword",repmat("QPSK",1,numCodewords), ...
                "QmPerCodeword",2*ones(1,numCodewords), ...
                "TargetCodeRatePerCodeword",(308/1024)*ones(1,numCodewords), ...
                "TBScalingPerCodeword",ones(1,numCodewords), ...
                "XOverhead",0, "NumLayers",rankValue, ...
                "NumCodewords",numCodewords, ...
                "LayerCountPerCodeword",layerCount, ...
                "DMRSConfigId","DMRS-STRICT-FIXTURE", ...
                "DMRSPortSet",0:rankValue-1, ...
                "PTRSConfigId",ptrsConfigId, ...
                "PTRSPortSet",ptrsPortSet, ...
                "NDIPerCodeword",ones(1,numCodewords), ...
                "RVPerCodeword",zeros(1,numCodewords), ...
                "HARQProcessId",0, ...
                "UECapability1024QAM",false, ...
                "RRCEnabled1024QAM",false, ...
                "DCIEnabled1024QAM",false, ...
                "DeploymentAllows1024QAM",false, ...
                "FrequencyRange","FR1", ...
                "OperatingBand","n78", ...
                "DeploymentClass","controlled_test", ...
                "FrequencyRangeAllows1024QAM",false, ...
                "BandAllows1024QAM",false);
            assignment = sixgr.pdsch.PDSCHAssignmentFactory.forCalibration( ...
                request,struct("AbsoluteSlot",0,"ResourceAvailable",true));
            if rankValue <= 4
                dmrsLength = 1;
            else
                dmrsLength = 2;
            end
            referenceData = struct( ...
                "NID",double(opt.NID), ...
                "DataScramblingIdentityNID",double(opt.NID), ...
                "DMRSConfigurationType",1, ...
                "DMRSTypeAPosition",2, ...
                "DMRSAdditionalPosition",0, ...
                "DMRSLength",dmrsLength, ...
                "NumCDMGroupsWithoutData",1 + double(rankValue > 2), ...
                "NIDNSCID",double(opt.NID), ...
                "NSCID",0, ...
                "DMRSMultiplexing","basic", ...
                "EnablePTRS",logical(opt.UsePTRS), ...
                "NPhysicalTxAntennas",rankValue, ...
                "OFDMOptions",{cell(1,0)}, ...
                "DMRSAmplitudeScale",1, ...
                "PTRSAmplitudeScale",1);
            if logical(opt.UsePTRS)
                referenceData.PTRSTimeDensity = 2;
                referenceData.PTRSFrequencyDensity = 2;
                referenceData.PTRSREOffset = "00";
            end
            referenceConfig = sixgr.pdsch.PDSCHReferenceSignalConfig( ...
                referenceData);
            referenceIndices = sixgr.pdsch. ...
                PDSCHReferenceSignalGenerator.resolveIndices( ...
                assignment,carrier,referenceConfig);
            ownership = sixgr.pdsch.PDSCHResourceOwnershipMap( ...
                allocation,struct());
            context = struct( ...
                "PRBSet",0:nPRB-1, "SymbolAllocation",[0 L], ...
                "GridNumPRB",nPRB, ...
                "GridSymbolsPerSlot",double(carrier.SymbolsPerSlot), ...
                "BWPStartPRB",0,"AbsoluteSlot",0, ...
                "UnavailableIndices",zeros(1,0), ...
                "DMRSIndicesPerPort", ...
                    {referenceIndices.DMRSIndicesPerPort}, ...
                "PTRSIndicesPerPort", ...
                    {referenceIndices.PTRSIndicesPerPort}, ...
                "DMRSLogicalPortSet", ...
                    referenceIndices.DMRSLogicalPortSet, ...
                "PTRSLogicalPortSet", ...
                    referenceIndices.PTRSLogicalPortSet, ...
                "LayerCountPerCodeword",layerCount, ...
                "QmPerCodeword",2*ones(1,numCodewords), ...
                "CodeBlockCountPerCodeword",ones(1,numCodewords), ...
                "ReferenceConfigurationDigest", ...
                    referenceConfig.ConfigurationDigest);
            resourcePlan = sixgr.pdsch.PDSCHResourcePlan(ownership,context);

            if logical(opt.FrequencySelective)
                prgSize = 2;
                nPRG = ceil(nPRB/prgSize);
                W = complex(zeros(rankValue,rankValue,nPRG,1));
                F = localDFT(rankValue);
                for prg = 1:nPRG
                    permutation = circshift(1:rankValue,prg-1);
                    W(:,:,prg,1) = diag(exp(1j*(0:rankValue-1).' ...
                        * prg/7)) * F(:,permutation);
                end
                mode = "prg_noncodebook";
            else
                prgSize = 0;
                nPRG = 1;
                W = reshape(eye(rankValue),rankValue,rankValue,1,1);
                mode = "wideband_fixed_matrix";
            end
            precoderSpec = struct( ...
                "Mode",mode, "NPorts",rankValue, "NLayers",rankValue, ...
                "NPRG",nPRG, "NSymbolGroups",1, "PRGSize",prgSize, ...
                "PRBSet",0:nPRB-1, "ScheduledSymbols",0:L-1, ...
                "SymbolGroupMap",zeros(1,L), "W",W, ...
                "MatrixSource","strict_chain_fixture", ...
                "CodebookIdentifier","", ...
                "NormalizationConvention","semi_unitary", ...
                "NormalizationTolerance",2e-12);
            precoder = sixgr.pdsch.PDSCHPrecoderBundle(precoderSpec);
            integrationContext = ...
                StrictPDSCHChainFixture.integrationContext( ...
                assignment, precoder);

            receiverConfig = struct( ...
                "TransportBlockSizes",double(opt.TransportBlockSize) ...
                    * ones(1,numCodewords), ...
                "ChannelModel","AWGN", "MaxIterations",20, ...
                "Algorithm","Normalized min-sum", ...
                "LLRConvention","positive_favours_bit_zero", ...
                "NPhysicalRxAntennas",rankValue, ...
                "NoiseVariance",0, ...
                "ReferenceChannelGain",ones(rankValue,1));
            transportBlocks = cell(1,numCodewords);
            for cw = 1:numCodewords
                index = (1:double(opt.TransportBlockSize)).';
                transportBlocks{cw} = int8(mod( ...
                    floor(index*(cw + 2)/3) + floor(index.^2/7) ...
                    + floor(index/11),2));
            end

            fixture = struct( ...
                "Assignment",assignment, "ResourcePlan",resourcePlan, ...
                "Carrier",carrier, "ReferenceConfig",referenceConfig, ...
                "ReceiverConfig",receiverConfig, ...
                "TransportBlocks",{transportBlocks}, ...
                "PrecoderBundle",precoder, ...
                "IntegrationContext",integrationContext);
        end

        function context = integrationContext(assignment, precoder)
            assignment.validateForExecution();
            data = assignment.toStruct();
            bwpRelative = double(data.PRBSetBWPRelative(:).');
            carrierRelative = double(data.PRBSetCarrierRelative(:).');
            startPRB = carrierRelative(1) - bwpRelative(1);
            if any(carrierRelative - bwpRelative ~= startPRB)
                error("StrictPDSCHChainFixture:BadBWPMapping", ...
                    "Fixture assignment has an inconsistent BWP-to-carrier map.");
            end
            tci = struct( ...
                "TCIStateId", double(data.TCIStateId), ...
                "Activated", true, ...
                "SourceReferenceSignal", "NZP-CSI-RS", ...
                "SourceReferenceSignalId", "CSI-RS-STRICT-FIXTURE", ...
                "QCLTypes", "A|D", ...
                "Assumptions", "delay_doppler_spatial_rx", ...
                "PrecoderContextId", ...
                    "PRECODER-TCI-" + string(data.TCIStateId), ...
                "PrecoderBundleDigest", precoder.ImmutableBundleDigest, ...
                "PrecoderAssignmentId", assignment.AssignmentId, ...
                "PrecoderAssignmentValidationDigest", ...
                    assignment.ExecutionValidationDigest, ...
                "PrecoderConfigurationEpoch", ...
                    double(data.ConfigurationEpoch));
            context = struct( ...
                "ActiveServingCellIds", unique([double(data.ServingCellId), ...
                    double(data.SchedulingCellId)]), ...
                "ActiveCCIds", double(data.CCId), ...
                "ActiveBWPId", double(data.BWPId), ...
                "ActiveBWPStartPRB", startPRB, ...
                "ActiveBWPNumPRB", ...
                    max(1, max(bwpRelative) + 1), ...
                "ConfigurationEpoch", double(data.ConfigurationEpoch), ...
                "CarrierIndicatorValid", true, ...
                "CrossCarrierSchedulingEnabled", true, ...
                "ActivatedTCIStates", tci);
        end

        function assignment = cloneAssignment(original,field,value)
            data = original.toStruct();
            data.(char(string(field))) = value;
            data.AssignmentId = string(data.AssignmentId) + "-TEST";
            assignment = sixgr.pdsch.PDSCHSchedulingAssignment(data);
        end

        function bundle = reversePRGBundle(original)
            W = original.W(:,:,end:-1:1,:);
            for prg = 1:original.NPRG
                staleLayerPhase = exp(1j*pi/2 ...
                    * mod((1:original.NLayerPorts) + prg,4));
                for group = 1:original.NSymbolGroups
                    W(:,:,prg,group) = W(:,:,prg,group) ...
                        * diag(staleLayerPhase);
                end
            end
            spec = struct( ...
                "Mode",original.Mode, ...
                "NPorts",original.NPhysicalTxAntennas, ...
                "NLayers",original.NLayerPorts, ...
                "NPRG",original.NPRG, ...
                "NSymbolGroups",original.NSymbolGroups, ...
                "PRGSize",original.PRGSize, ...
                "PRBSet",original.PRBSet, ...
                "ScheduledSymbols",original.ScheduledSymbols, ...
                "SymbolGroupMap",original.SymbolGroupIndexPerSymbol, ...
                "W",W, "MatrixSource","wrong_prg_test", ...
                "CodebookIdentifier",original.CodebookIdentifier, ...
                "NormalizationConvention",original.NormalizationConvention, ...
                "NormalizationTolerance",original.NormalizationTolerance);
            bundle = sixgr.pdsch.PDSCHPrecoderBundle(spec);
        end
    end
end

function F = localDFT(order)
row = (0:order-1).';
column = 0:order-1;
F = exp(-1j*2*pi*row*column/order)/sqrt(order);
end
