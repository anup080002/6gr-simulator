classdef PDSCHPhaseTestSupport
    %PDSCHPhaseTestSupport Test-only fixtures for the frozen Prompt-02 pack.

    methods (Static)
        function root = vectorRoot()
            repo = fileparts(fileparts(fileparts(mfilename("fullpath"))));
            root = fullfile(repo, "tests", "vectors", "pdsch");
        end

        function [assignment, observedError] = assignmentFromVector(row)
            profile = lower(string(row.Profile));
            [decoded, ue, frame, harq] = ...
                PDSCHPhaseTestSupport.assignmentInputs(row);
            assignment = [];
            observedError = "";
            try
                switch profile
                    case {"connected_strict","ra_si_strict"}
                        assignment = sixgr.pdsch.PDSCHAssignmentFactory.fromDecodedDCI( ...
                            decoded, sixgr.pdsch.PDSCHUEContext(ue), frame, harq);
                    case "sps_strict"
                        sps = PDSCHPhaseTestSupport.spsContext(row, decoded);
                        assignment = sixgr.pdsch.PDSCHAssignmentFactory.fromSPSOccasion( ...
                            sixgr.pdsch.PDSCHSPSContext(sps), ...
                            sixgr.pdsch.PDSCHUEContext(ue), frame, harq);
                    case "phy_calibration"
                        request = PDSCHPhaseTestSupport.calibrationRequest(decoded, ue);
                        assignment = sixgr.pdsch.PDSCHAssignmentFactory.forCalibration( ...
                            request, frame);
                    otherwise
                        error("sixgr:pdsch:UnsupportedExecutionProfile", ...
                            "Unsupported test profile '%s'.", profile);
                end
            catch ME
                observedError = string(ME.identifier);
            end
        end

        function [decoded, ue, frame, harq] = assignmentInputs(row)
            startPRB = double(row.PRBStart);
            nPRB = double(row.PRBLength);
            prbSet = startPRB:(startPRB + nPRB - 1);
            tableName = string(row.MCSTable);
            mcsIndex = double(row.MCSIndex);
            mcsContext = struct( ...
                "NumCodewords", 1, ...
                "NumLayers", 1, ...
                "UECapability1024QAM", true, ...
                "UECapability1024QAMVariant", ...
                    "pdsch-1024qam-fr1-r17", ...
                "MaxNumberMIMOLayersPDSCH", 8, ...
                "RRCEnabled1024QAM", true, ...
                "DCIEnabled1024QAM", true, ...
                "DCIFormat", string(row.DCIFormat), ...
                "DeploymentAllows1024QAM", true, ...
                "FrequencyRange", "FR1", ...
                "OperatingBand", "n78", ...
                "DeploymentClass", "controlled_test", ...
                "FrequencyRangeAllows1024QAM", true, ...
                "BandAllows1024QAM", true, ...
                "RNTIType", string(row.RNTIType), ...
                "SelectionSource", "decoded_dci+rrc_context");
            try
                mcs = sixgr.pdsch.PDSCHMCSResolver.resolve( ...
                    tableName, mcsIndex, mcsContext);
                modulation = string(mcs.Modulation);
                qm = double(mcs.Qm);
                rate = double(mcs.TargetCodeRate);
            catch
                % Assignment negative rows intentionally reject before MCS
                % materialization. Keep their test fixture dimensionally valid.
                modulation = "QPSK";
                qm = 2;
                rate = 120 / 1024;
            end
            decoded = struct( ...
                "Present", logical(row.DecodedDCIPresent), ...
                "Id", string(row.DecodedDCIId), ...
                "CRCPass", logical(row.DCICRCPass), ...
                "RNTIMatch", logical(row.DCIRNTIMatch), ...
                "FieldsInRange", logical(row.DCIFieldsInRange), ...
                "Format", string(row.DCIFormat), ...
                "RNTI", 4660, ...
                "DecodedRNTI", 4660, ...
                "RNTIType", string(row.RNTIType), ...
                "DCIEnabled1024QAM", true, ...
                "PDCCHAbsoluteSlot", max(0, double(row.AbsoluteSlot) - double(row.K0)), ...
                "SearchSpaceId", "SS-0", ...
                "CORESETId", "CORESET-0", ...
                "FDRAType", string(row.FDRAType), ...
                "FrequencyDomainAssignmentRaw", sprintf("%d:%d", startPRB, nPRB), ...
                "RBGSize", 2, ...
                "VRBToPRBMapping", string(row.VRBToPRBMapping), ...
                "InterleaverBundleSize", 2, ...
                "PRBSetBWPRelative", prbSet, ...
                "PRBSetCarrierRelative", prbSet, ...
                "TDRAListId", "TDRA-0", ...
                "TDRARowIndex", 0, ...
                "K0", double(row.K0), ...
                "SLIV", NaN, ...
                "SymbolAllocation", [double(row.StartSymbol), double(row.SymbolLength)], ...
                "MappingType", string(row.MappingType), ...
                "MCSTablePerCodeword", tableName, ...
                "MCSIndexPerCodeword", mcsIndex, ...
                "ModulationPerCodeword", modulation, ...
                "QmPerCodeword", qm, ...
                "TargetCodeRatePerCodeword", rate, ...
                "TBScalingPerCodeword", 1, ...
                "XOverhead", 0, ...
                "NumLayers", 1, ...
                "NumCodewords", 1, ...
                "LayerCountPerCodeword", 1, ...
                "AntennaPortField", double(row.AntennaPortField), ...
                "DMRSConfigId", "DMRS-0", ...
                "DMRSPortSet", 0, ...
                "PTRSConfigId", "", ...
                "PTRSPortSet", [], ...
                "NDIPerCodeword", double(row.NDI), ...
                "RVPerCodeword", double(row.RV), ...
                "DAI", 0, ...
                "TCIStateId", double(row.TCIStateId), ...
                "RateMatchPatternIds", strings(1,0), ...
                "ZPCSIRSResourceIds", strings(1,0), ...
                "TransmissionConfigurationIndication", double(row.TCIStateId));
            ue = struct( ...
                "UEId", 1, ...
                "ServingCellId", double(row.ServingCellID), ...
                "SchedulingCellId", double(row.ServingCellID), ...
                "CCId", double(row.CCID), ...
                "BWPId", double(row.BWPId), ...
                "ConfigurationEpoch", double(row.ConfigurationEpoch), ...
                "ActiveBWPContextPresent", logical(row.ActiveBWPContextPresent), ...
                "EpochCurrent", logical(row.UEContextEpochCurrent), ...
                "ServingCellActive", logical(row.ServingCellActive), ...
                "MCSContextSupported", logical(row.MCSContextSupported), ...
                "TCIStateActive", logical(row.TCIStateActive), ...
                "UECapability1024QAM", true, ...
                "UECapability1024QAMVariant", ...
                    "pdsch-1024qam-fr1-r17", ...
                "MaxNumberMIMOLayersPDSCH", 8, ...
                "RRCEnabled1024QAM", true, ...
                "DeploymentAllows1024QAM", true, ...
                "FrequencyRange", "FR1", ...
                "OperatingBand", "n78", ...
                "DeploymentClass", "controlled_test", ...
                "FrequencyRangeAllows1024QAM", true, ...
                "BandAllows1024QAM", true);
            frame = struct( ...
                "AbsoluteSlot", double(row.AbsoluteSlot), ...
                "ResourceAvailable", logical(row.ResourceAvailable));
            harq = struct( ...
                "ProcessId", double(row.HARQProcessID), ...
                "Consistent", logical(row.HARQContextConsistent));
        end

        function sps = spsContext(row, decoded)
            sps = struct( ...
                "ConfigurationPresent", logical(row.SPSConfigPresent), ...
                "ConfigId", "SPS-1", ...
                "ConfigurationEpoch", double(row.ConfigurationEpoch), ...
                "ActivationDCIId", string(row.SPSActivationDCIId), ...
                "ActivationDCIFormat", string(row.DCIFormat), ...
                "ActivationDCICRCPass", logical(row.SPSActivationDCICRCPass), ...
                "ActivationDCIRNTIMatch", logical(row.SPSActivationDCIRNTIMatch), ...
                "Activated", logical(row.SPSActivated), ...
                "Released", logical(row.SPSReleased), ...
                "OccasionMatch", logical(row.SPSOccasionMatch), ...
                "OccasionIndex", max(0, floor(double(row.AbsoluteSlot) / 10)), ...
                "Assignment", decoded);
        end

        function request = calibrationRequest(decoded, ue)
            names = [ ...
                "RNTI","RNTIType","PRBSetBWPRelative", ...
                "PRBSetCarrierRelative","SymbolAllocation","MappingType", ...
                "MCSTablePerCodeword","MCSIndexPerCodeword", ...
                "ModulationPerCodeword","QmPerCodeword", ...
                "TargetCodeRatePerCodeword","TBScalingPerCodeword", ...
                "XOverhead","NumLayers","NumCodewords", ...
                "LayerCountPerCodeword","DMRSPortSet","NDIPerCodeword", ...
                "RVPerCodeword","DCIEnabled1024QAM"];
            request = struct();
            for idx = 1:numel(names)
                request.(names(idx)) = decoded.(names(idx));
            end
            request.DCIFormat = decoded.Format;
            request.UEId = ue.UEId;
            request.ServingCellId = ue.ServingCellId;
            request.SchedulingCellId = ue.SchedulingCellId;
            request.CCId = ue.CCId;
            request.BWPId = ue.BWPId;
            request.ConfigurationEpoch = ue.ConfigurationEpoch;
            request.HARQProcessId = 0;
            request.UECapability1024QAM = ue.UECapability1024QAM;
            request.UECapability1024QAMVariant = ...
                ue.UECapability1024QAMVariant;
            request.MaxNumberMIMOLayersPDSCH = ...
                ue.MaxNumberMIMOLayersPDSCH;
            request.RRCEnabled1024QAM = ue.RRCEnabled1024QAM;
            request.DeploymentAllows1024QAM = ue.DeploymentAllows1024QAM;
            request.FrequencyRange = ue.FrequencyRange;
            request.OperatingBand = ue.OperatingBand;
            request.DeploymentClass = ue.DeploymentClass;
            request.FrequencyRangeAllows1024QAM = ...
                ue.FrequencyRangeAllows1024QAM;
            request.BandAllows1024QAM = ue.BandAllows1024QAM;
        end

        function carrier = carrier(nPRB, scs)
            if nargin < 1, nPRB = 24; end
            if nargin < 2, scs = 30; end
            carrier = nrCarrierConfig;
            carrier.NCellID = 42;
            carrier.NSizeGrid = nPRB;
            carrier.NStartGrid = 0;
            carrier.SubcarrierSpacing = scs;
            carrier.CyclicPrefix = "normal";
            carrier.NSlot = 0;
            carrier.NFrame = 0;
        end

        function pdsch = pdsch(carrier, rank, modulation, mappingType)
            if nargin < 4, mappingType = "A"; end
            pdsch = nrPDSCHConfig;
            pdsch.NID = carrier.NCellID;
            pdsch.RNTI = 4660;
            pdsch.PRBSet = 0:(carrier.NSizeGrid - 1);
            pdsch.SymbolAllocation = [0 14];
            pdsch.MappingType = char(string(mappingType));
            pdsch.Modulation = char(string(modulation));
            pdsch.NumLayers = rank;
            pdsch.DMRS.DMRSConfigurationType = 1;
            pdsch.DMRS.DMRSTypeAPosition = 2;
            pdsch.DMRS.DMRSAdditionalPosition = 1;
            pdsch.DMRS.DMRSLength = 1;
            pdsch.DMRS.NumCDMGroupsWithoutData = min(2, rank);
            pdsch.DMRS.DMRSPortSet = 0:(rank - 1);
        end

        function id = fullError(token)
            id = "sixgr:pdsch:" + string(token);
        end

        function obs = harqObservation(varargin)
            values = struct( ...
                "UEId", 1, "ServingCellId", 1, "SchedulingCellId", 1, ...
                "CCId", 0, "BWPId", 0, "HARQProcessId", 3, ...
                "CodewordIndex", 0, "ConfigurationEpoch", 7, ...
                "NDI", 1, "NewData", true, "RV", 0, ...
                "TBIdentityDigest", "TB-A", "TBS", 1024, ...
                "CodingPlanDigest", "LAYOUT-A", "BaseGraph", 2, ...
                "LiftingSize", 64, "CodeBlockLayout", struct("C",1,"K",640), ...
                "FillerPositions", {cell(1,1)}, "Ncb", 3200, "Nref", 3200, ...
                "RateRecoveredLLR", ones(32,1), ...
                "ValidPositionMask", true(32,1), "DecodeOK", false);
            if mod(numel(varargin), 2) ~= 0
                error("PDSCHPhaseTestSupport:BadHARQOptions", ...
                    "HARQ fixture options must be name-value pairs.");
            end
            for idx = 1:2:numel(varargin)
                values.(char(string(varargin{idx}))) = varargin{idx + 1};
            end
            obs = values;
        end

        function [context, bundle] = integrationContext(assignment, bundle)
            data = assignment.toStruct();
            if nargin < 2 || isempty(bundle)
                allocatedSymbols = double(data.SymbolAllocation(1)) ...
                    + (0:double(data.SymbolAllocation(2))-1);
                bundle = PDSCHPhaseTestSupport.identityPrecoder( ...
                    double(data.NumLayers), ...
                    double(data.PRBSetCarrierRelative), allocatedSymbols);
            end
            assignmentDigest = assignment.validateForExecution();
            bwpRelative = double(data.PRBSetBWPRelative(:).');
            carrierRelative = double(data.PRBSetCarrierRelative(:).');
            startPRB = carrierRelative(1) - bwpRelative(1);
            assert(all(carrierRelative - bwpRelative == startPRB));
            tci = struct( ...
                "TCIStateId", double(data.TCIStateId), ...
                "Activated", true, ...
                "SourceReferenceSignal", "NZP-CSI-RS", ...
                "SourceReferenceSignalId", "CSI-RS-7", ...
                "QCLTypes", "A|D", ...
                "Assumptions", "delay_doppler_spatial_rx", ...
                "PrecoderContextId", ...
                    "PRECODER-TCI-" + string(data.TCIStateId), ...
                "PrecoderBundleDigest", bundle.ImmutableBundleDigest, ...
                "PrecoderAssignmentId", assignment.AssignmentId, ...
                "PrecoderAssignmentValidationDigest", assignmentDigest, ...
                "PrecoderConfigurationEpoch", ...
                    double(data.ConfigurationEpoch));
            context = struct( ...
                "ActiveServingCellIds", unique([double(data.ServingCellId), ...
                    double(data.SchedulingCellId)]), ...
                "ActiveCCIds", double(data.CCId), ...
                "ActiveBWPId", double(data.BWPId), ...
                "ActiveBWPStartPRB", startPRB, ...
                "ActiveBWPNumPRB", max(24, max(double(data.PRBSetBWPRelative)) + 1), ...
                "ConfigurationEpoch", double(data.ConfigurationEpoch), ...
                "CarrierIndicatorValid", true, ...
                "CrossCarrierSchedulingEnabled", true, ...
                "ActivatedTCIStates", tci);
        end

        function bundle = identityPrecoder(rank, prbSet, symbols)
            spec = struct( ...
                "Mode", "wideband_fixed_matrix", ...
                "NPorts", rank, ...
                "NLayers", rank, ...
                "NPRG", 1, ...
                "NSymbolGroups", 1, ...
                "PRGSize", 0, ...
                "PRBSet", double(prbSet(:).'), ...
                "ScheduledSymbols", double(symbols(:).'), ...
                "SymbolGroupMap", zeros(1, numel(symbols)), ...
                "W", eye(rank), ...
                "MatrixSource", "test_explicit_identity", ...
                "CodebookIdentifier", "", ...
                "NormalizationConvention", "semi_unitary");
            bundle = sixgr.pdsch.PDSCHPrecoderBundle(spec);
        end
    end
