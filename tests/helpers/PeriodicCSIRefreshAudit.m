classdef PeriodicCSIRefreshAudit
    % Test-only snapshots of actual runtime tables; never creates feedback.
    methods (Static)
        function entry=capture(state)
            owner=state.SharedWaveformStream;
            apps=sixgr.util.structGet(state,'TestRankTransitionApplications',{});
            if logical(sixgr.util.structGet(state,'TestSRSContinuationCompleted',false))
                apps{end+1}=state.TestSRSContinuationApplication;
            end
            entry=struct('Slot',state.CurrentSlot,'AtSample',owner.Events.NextSampleIndex, ...
                'SampleRateHz',owner.SampleRateHz,'ClockEpoch',owner.Physical.ConfigurationEpoch, ...
                'ULCompletions',localCompletions(apps),'PendingCSI',state.PendingCSITable, ...
                'ReceivedCSI',sixgr.util.structGet(state,'ControlTrials.CSIRS',table()), ...
                'ULTrials',sixgr.util.structGet(state,'TestPublishedULTrials',table()));
        end

        function proof=verify(snapshots)
            % A fresh UE payload is NOT yet decoded UCI. Require a measured
            % UL completion first, then a same-obligation source refresh.
            proof=struct('Observed',false,'Witnesses',table(), ...
                'Scope',"actual_UL_trial_then_periodic_CSI_payload_refresh_not_UCI_delivery", ...
                'FullScenarioQualified',false,'StatisticalQualification',false);
            assert(iscell(snapshots),'test:CSIRefreshSnapshots','Keep original ordered snapshots.');
            clocks=["SpatialDecisionSourceSlot","SpatialDecisionDeliveredSlot", ...
                "QualityMeasurementSourceSlot","QualityMeasurementDeliveredSlot"];
            for k=2:numel(snapshots)
                before=snapshots{k-1}; after=snapshots{k};
                assert(isfinite(before.AtSample)&&isfinite(after.AtSample)&& ...
                    before.AtSample>=0&&after.AtSample>=before.AtSample && ...
                    isfinite(before.SampleRateHz)&&before.SampleRateHz>0&& ...
                    after.SampleRateHz==before.SampleRateHz && ...
                    isfinite(before.ClockEpoch)&&before.ClockEpoch>=0&& ...
                    after.ClockEpoch==before.ClockEpoch, ...
                    'test:CSIRefreshClock','Original physical clock must not move backwards.');
                a=before.PendingCSI; b=after.PendingCSI;
                if isempty(a)||isempty(b)||isempty(before.ULTrials), continue; end
                assert(all(ismember(clocks,string(b.Properties.VariableNames))), ...
                    'test:CSIRefreshSchema','Actual producer lost adaptation clock columns.');
                ul=a(string(a.Direction)=="UL" & a.Processed & ...
                    string(a.SourceSignal)=="PUSCH-DMRS" & ...
                    string(a.AdaptationDeliveryStatus)=="accepted_new_feedback_delivery" & ...
                    isfinite(a.QualityMeasurementSourceSlot) & ...
                    a.SourceSlot==a.QualityMeasurementSourceSlot & ...
                    isfinite(a.DeliveredSlot) & a.DeliveredSlot==a.QualityMeasurementDeliveredSlot & ...
                    a.DeliveredSlot<=before.Slot,:);
                if isempty(ul), continue; end
                for j=1:height(b)
                    if string(b.Direction(j))~="DL" || b.Processed(j), continue; end
                    hit=find(string(a.ReportIdentity)==string(b.ReportIdentity(j)));
                    if ~isscalar(hit)||a.Processed(hit)||~(b.SourceSlot(j)>a.SourceSlot(hit)), continue; end
                    assert(string(a.Direction(hit))=="DL" && a.UEIndex(hit)==b.UEIndex(j) && ...
                        ~a.RightCensored(hit)&&~b.RightCensored(j)&& ...
                        string(a.CSIUCITransport(hit))=="pucch"&& ...
                        string(b.CSIUCITransport(j))=="pucch"&& ...
                        ~a.CSIUCIMultiplexedOnPUSCH(hit)&&~b.CSIUCIMultiplexedOnPUSCH(j)&& ...
                        isfinite(b.DueSlot(j))&&b.DueSlot(j)>after.Slot&& ...
                        isequaln(a.DueSlot(hit),b.DueSlot(j)) && ...
                        isequaln(a.CSIReferenceSlot(hit),b.CSIReferenceSlot(j)) && ...
                        string(a.CSIReportConfigID(hit))==string(b.CSIReportConfigID(j)) && ...
                        isequaln(a.CSIConfigurationEpoch(hit),b.CSIConfigurationEpoch(j)) && ...
                        a.RNTI(hit)==b.RNTI(j)&&a.ServingCell(hit)==b.ServingCell(j)&& ...
                        string(b.SourceSignal(j))=="CSI-RS"&&b.SourceSlot(j)<=b.CSIReferenceSlot(j), ...
                        'test:CSIRefreshObligation','A refresh must preserve the installed periodic obligation.');
                    data=before.ULTrials;
                    sameUE=ul(ul.UEIndex==b.UEIndex(j),:);
                    linked=find(data.UEIndex==b.UEIndex(j) & ...
                        ismember(data.Slot,sameUE.QualityMeasurementSourceSlot));
                    if isempty(linked), continue; end
                    selected=linked(end);
                    assert(nnz(data.UEIndex==data.UEIndex(selected)&data.Slot==data.Slot(selected))==1, ...
                        'test:CSIRefreshULCompletion','An ambiguous same-slot quality source cannot identify one received grant.');
                    completed=localCompletedTrial(before,data(selected,:));
                    source=after.ReceivedCSI;
                    hitSource=find(source.UEIndex==b.UEIndex(j) & source.ServingCell==b.ServingCell(j) & ...
                        source.Slot==b.SourceSlot(j) & ...
                        string(source.CSIMeasurementID)==string(b.CSIMeasurementID(j)) & ...
                        string(source.CSIMeasurementDigest)==string(b.CSIMeasurementDigest(j)));
                    assert(isscalar(hitSource),'test:CSIRefreshSource','Refresh must retain one exact received CSI measurement.');
                    source=source(hitSource,:);
                    assert(isfinite(source.ResultAvailableAtSample)&&source.ResultAvailableAtSample<=after.AtSample, ...
                        'test:CSIRefreshFutureSource','Refreshed source must already be available on the original clock.');
                    [~,usable,clocked]=sixgr.truth.csirsMeasurementAvailability(source,true);
                    assert(usable&&clocked&&source.MeasurementClockEpoch==after.ClockEpoch&& ...
                        source.ObservationSampleRateHz==after.SampleRateHz&& ...
                        b.MeasurementClockEpoch(j)==after.ClockEpoch&& ...
                        string(b.MeasurementClockDomain(j))=="shared_receiver_sample_clock/v1"&& ...
                        b.MeasurementAvailableAtSample(j)==source.ResultAvailableAtSample, ...
                        'test:CSIRefreshMeasurementClock','Bind the pending payload to its actual receiver clock.');
                    for field=["CSIMeasurementID","CSIMeasurementDigest","ReceiverWindowID"]
                        assert(~ismissing(string(source.(field)))&&strlength(strtrim(string(source.(field))))>0, ...
                            'test:CSIRefreshSource','Actual measurement identity must not be empty.');
                    end
                    for field=["CSIReportConfigID","CSIConfigurationEpoch","CSIUCIChannel", ...
                            "CQI","RI","PMI", ...
                            "PMI_I11","PMI_I12","PMI_I13","PMI_I2","LI"]
                        x=b.(field)(j,:); y=source.(field);
                        if ischar(x)||isstring(x)||iscell(x), x=string(x); y=string(y); end
                        assert(isequaln(x,y),'test:CSIRefreshPayload', ...
                            'A refreshed source slot cannot retain a different measurement payload (%s).',field);
                    end
                    % The measured encoder emits uint8; pending UCI stores
                    % int8. RawCSVArrayCodec intentionally includes class
                    % and shape, so token equality is not bit equality.
                    % Validate BEFORE conversion, retaining exact length
                    % and order; never round fractional/nonbinary values.
                    for field=["CSIPart1BitsToken","CSIPart2BitsToken"]
                        x=localBits(b.(field)(j,:),field);
                        y=localBits(source.(field),field);
                        assert(isequal(x,y),'test:CSIRefreshPayload', ...
                            'Refreshed %s differs from its measured binary sequence.',field);
                    end
                    assert(all(isnan(b{j,cellstr(clocks)})) && ~b.CSIUCIDecodeOk(j) && ...
                        isnan(b.CRCPass(j)) && isnan(b.DeliveredSlot(j))&& ...
                        isnan(b.AvailableAtSample(j))&&isnan(b.ReceiverClockEpoch(j))&& ...
                        strlength(string(b.ObservationID(j)))==0&& ...
                        strlength(string(b.ReceiverContextDigest(j)))==0&& ...
                        isnan(b.CSIUCICRCPass(j))&&strlength(string(b.CSIUCIDecodedBitsToken(j)))==0, ...
                        'test:CSIRefreshPrematureAuthority','Payload refresh cannot invent delivered UCI or clocks.');
                    witness=table(after.Slot,after.AtSample,string(b.ReportIdentity(j)), ...
                        a.SourceSlot(hit),b.SourceSlot(j),b.DueSlot(j),data.Slot(linked(end)), ...
                        'VariableNames',{'ObservedAtSlot','ObservedAtSample','ReportIdentity', ...
                        'PreviousCSISourceSlot','RefreshedCSISourceSlot','ReportDueSlot','CompletedULSlot'});
                    witness.CSIMeasurementID=string(source.CSIMeasurementID);
                    witness.CSIMeasurementDigest=string(source.CSIMeasurementDigest);
                    witness.CSIReceiverWindowID=string(source.ReceiverWindowID);
                    witness.ULTransmissionID=string(completed.TransmissionID);
                    witness.ULReceiverObservationID=string(completed.ReceiverObservationID);
                    witness.ULCompletedAtSample=completed.CompletedAtSample;
                    proof.Witnesses=[proof.Witnesses;witness]; %#ok<AGROW>
                end
            end
            proof.Observed=height(proof.Witnesses)>0;
        end
    end
end

function bits=localBits(token,field)
try
    bits=sixgr.runtime.RawCSVArrayCodec.decode(token);
catch cause
    error('test:CSIRefreshPayload','Invalid %s token: %s',field,cause.message);
end
assert((isnumeric(bits)||islogical(bits))&&isreal(bits)&& ...
    ismatrix(bits)&&(isvector(bits)||isempty(bits))&& ...
    all(isfinite(bits(:)))&&all(bits(:)==0|bits(:)==1), ...
    'test:CSIRefreshPayload','%s must retain a finite binary vector, not soft values or a matrix.',field);
assert(field~="CSIPart1BitsToken"||~isempty(bits),'test:CSIRefreshPayload', ...
    'A prepared periodic CSI report must retain its nonempty Part 1.');
bits=double(bits(:));
end

function rows=localCompletions(apps)
% Copy only already-checked original metadata, never IQ or live handles.
rows=table();
for k=1:numel(apps)
    a=apps{k}; g=a.ScheduledGrant; id=a.TransmissionReceipt.Identity;
    assert(a.WaveformApplicationVerified&&string(g.Direction)=="UL"&& ...
        string(g.PHYGrant.GrantContextId)==string(id.PHYGrantContextId), ...
        'test:CSIRefreshULCompletion','Use original completed UL applications.');
    row=table(g.UEIndex,g.Slot,string(g.PHYGrant.GrantContextId),string(id.TransmissionID), ...
        string(a.ReceiverObservationID),a.ReceiverStartSample,a.ReceiverEndSampleExclusive, ...
        a.ReceiverSampleRateHz,string(a.ReceiverSampleSHA256),a.CompletedAtSample, ...
        logical(a.DecodeAttempted),double(a.CRCPass),id.EndSampleExclusive,id.SampleRateHz, ...
        'VariableNames',{'UEIndex','Slot','FrozenGrantContextId','TransmissionID','ReceiverObservationID', ...
        'ReceiverStartSample','ReceiverEndSampleExclusive','ReceiverSampleRateHz','ReceiverSampleSHA256', ...
        'CompletedAtSample','DecodeAttempted','CRCPass','TransmitEndSampleExclusive','TransmitSampleRateHz'});
    if ~isempty(rows)
        same=find(rows.TransmissionID==row.TransmissionID);
        if ~isempty(same)
            assert(isscalar(same)&&isequaln(rows(same,:),row),'test:CSIRefreshULCompletion', ...
                'The same original completion cannot change between snapshot sources.');
            continue;
        end
    end
    rows=[rows;row]; %#ok<AGROW>
end
end

function completed=localCompletedTrial(snapshot,trial)
rows=snapshot.ULCompletions;
assert(~isempty(rows),'test:CSIRefreshULCompletion','A slot match alone is not completed PHY evidence.');
hit=find(rows.FrozenGrantContextId==string(trial.FrozenGrantContextId));
assert(isscalar(hit),'test:CSIRefreshULCompletion','Require one original completion for the exact published grant.');
completed=rows(hit,:);
assert(completed.UEIndex==trial.UEIndex&&completed.Slot==trial.Slot&& ...
    completed.DecodeAttempted&&trial.ULSCHDecodeAttempted&& ...
    any(completed.CRCPass==[0 1])&&isequaln(completed.CRCPass,double(trial.CRCPass))&& ...
    isfinite(completed.CompletedAtSample)&&completed.CompletedAtSample<=snapshot.AtSample&& ...
    completed.ReceiverStartSample>=0&&completed.ReceiverEndSampleExclusive>completed.ReceiverStartSample&& ...
    completed.ReceiverEndSampleExclusive<=completed.CompletedAtSample&& ...
    completed.TransmitEndSampleExclusive>0&& ...
    completed.TransmitEndSampleExclusive<=completed.CompletedAtSample&& ...
    completed.ReceiverSampleRateHz==snapshot.SampleRateHz&&completed.TransmitSampleRateHz==snapshot.SampleRateHz, ...
    'test:CSIRefreshULCompletion','Original decode/identity/clock must precede the observed refresh.');
for field=["FrozenGrantContextId","TransmissionID","ReceiverObservationID","ReceiverSampleSHA256"]
    value=string(completed.(field));
    assert(~ismissing(value)&&strlength(strtrim(value))>0,'test:CSIRefreshULCompletion','Missing original UL identity.');
end
end
