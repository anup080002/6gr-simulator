function ok=testRetainedScheduledOperatingPointEvidence(inputPaths,outputFolder)
% Reporting-only reprojection of original actual CSVs; never executes RF.
arguments
    inputPaths {mustBeText}
    outputFolder {mustBeTextScalar}
end
inputPaths=string(inputPaths(:)); outputFolder=string(outputFolder);
assert(~isempty(inputPaths)&&all(isfile(inputPaths))&& ...
    ~isfolder(outputFolder)&&~isfile(outputFolder), ...
    'test:RetainedProjectionPaths','Require original CSVs and a new separate audit directory.');
mkdir(outputFolder);
records=cell(numel(inputPaths),1);
for k=1:numel(inputPaths)
    source=string(sixgr.util.canonicalPath(inputPaths(k)));
    before=sixgr.util.sha256File(source);
    original=sixgr.util.csvReadTable(source);
    assert(height(original)>0 && all(ismember( ...
        ["AdaptiveMode","LinkAdaptationScheduled","MCSIndex","Modulation", ...
        "FrozenGrantContextId","PDCCHGrantBindingOk"], ...
        string(original.Properties.VariableNames))));
    % These retained physical fixtures carry explicit original grant and DCI
    % authority; no replacement values are supplied to the projector.
    expected=double(original.AdaptiveMode)==1 & ...
        double(original.LinkAdaptationScheduled)==0 & ...
        double(original.PDCCHGrantBindingOk)==1 & ...
        strlength(string(original.FrozenGrantContextId))>0;
    assert(any(expected),'test:NoRetainedRegression','Input must reproduce the consumed-report case.');
    projected=sixgr.link.applyScheduledOperatingPointEvidence(original);
    assert(all(projected.ScheduledMCS(expected)==original.MCSIndex(expected))&& ...
        all(projected.ScheduledMCSIndex(expected)==original.MCSIndex(expected))&& ...
        all(string(projected.ScheduledModulation(expected))==string(original.Modulation(expected)))&& ...
        all(projected.ScheduledOperatingPointMatchesTransmitted(expected)));
    projectedColumns=["ScheduledMCS","ScheduledMCSIndex","ScheduledModulation", ...
        "ScheduledOperatingPointSource","ScheduledOperatingPointEvidenceStatus", ...
        "ScheduledOperatingPointMatchesTransmitted"];
    untouched=setdiff(string(original.Properties.VariableNames),projectedColumns,'stable');
    assert(isequaln(original(:,cellstr(untouched)),projected(:,cellstr(untouched))), ...
        'test:ProjectionMutation','Receiver values, future feedback flags and identities must remain unchanged.');
    target=fullfile(outputFolder,"reprojected_"+string(k)+".csv");
    sixgr.util.csvWriteTable(target,projected,'PreserveSchema',true);
    assert(string(sixgr.util.sha256File(source))==string(before),'Original CSV changed.');
    records{k}=struct('SourcePath',source,'SourceSHA256',before, ...
        'Rows',height(original),'ReproducingRows',nnz(expected), ...
        'OutputPath',target,'OutputSHA256',sixgr.util.sha256File(target), ...
        'EvidenceScope','reporting_only_original_received_rows_no_new_RF_execution');
end
sixgr.util.jsonWrite(fullfile(outputFolder,'reprojection_receipt.json'), ...
    struct('Ok',true,'OriginalsUnchanged',true,'RFExecutions',0,'Inputs',{records}));
ok=true;
end
