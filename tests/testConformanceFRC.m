function entry = localCatalogEntry(entries, entryId)
matches = false(numel(entries), 1);
for index = 1:numel(entries)
    candidate = localSequenceItem(entries, index);
    matches(index) = string(candidate.id) == string(entryId);
end
indices = find(matches);
assert(numel(indices) == 1, ...
    "Expected exactly one FRC catalog record with id '%s'.", entryId);
entry = localSequenceItem(entries, indices);
end

function value = localSequenceItem(sequence, index)
if iscell(sequence)
    value = sequence{index};
else
    value = sequence(index);
end
end

function localAssertText(actual, expected, label)
assert(string(actual) == string(expected), ...
    "%s is '%s'; expected '%s'.", ...
    label, string(actual), string(expected));
end

function localAssertNear(actual, expected, label)
actual = double(actual);
expected = double(expected);
tolerance = max(1e-12, 64 * eps(max(abs(expected), 1)));
assert(isscalar(actual) && isfinite(actual) && ...
    abs(actual - expected) <= tolerance, ...
    "%s is %.15g; expected %.15g.", label, actual, expected);
end

function localThrowFailure(identifier, heading, diagnostics, varargin)
diagnostics = string(diagnostics);
diagnostics = diagnostics(strlength(diagnostics) > 0);
if isempty(diagnostics)
    details = "(no diagnostic detail was produced)";
else
    details = strjoin("  - " + diagnostics, newline);
end
headingText = string(sprintf(char(heading), varargin{:}));
message = strjoin([headingText; string(details(:))], string(newline));
error(char(identifier), "%s", char(message));
end

function tf = localTextScalar(value)
tf = ischar(value) || (isstring(value) && isscalar(value));
end

function tf = localLogicalScalar(value)
tf = (islogical(value) || isnumeric(value)) && isscalar(value) && ...
    isfinite(double(value)) && any(double(value) == [0, 1]);
end
