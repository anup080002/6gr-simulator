function ok = testConformanceFRC(varargin)
%TESTCONFORMANCEFRC Run the standards-anchored mandatory NR FRC gate.
%
%   testConformanceFRC() runs the real complete-waveform truth-chain gate.
%   It does not use LUT, logistic, fast-proxy, synthetic, or fallback rows.
%
%   testConformanceFRC("Profile","contract-only") intentionally limits the
%   test to catalog anchors plus exact Tx TBS/G setup validation. This
%   profile never reports a conformance point as passed. The same explicit
%   opt-in is available to constrained CI jobs through:
%
%       SIXGR_FRC_TEST_PROFILE=contract-only
%
%   With no explicit profile the real gate is mandatory. testAll invokes
%   testConformanceFRCContract instead so the ordinary regression suite
%   remains bounded. A setup-only, statistically unqualified, or incomplete
%   selected data-channel reproduction can never satisfy the real gate.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
opt = localParseOptions(varargin{:});

catalog = sixgr.conformance.frcCatalog();
localAssertCatalogAnchors(catalog);
mandatory = localMandatoryCases();

[preflight, preflightDiagnostics] = localPreflight(mandatory);
emptyReport = localReportFromPreflight(mandatory, preflight);

if opt.Profile == "contract-only"
    disp(emptyReport);
    setupFailures = ~reshape([preflight.SetupPass], [], 1);
    if any(setupFailures)
        localThrowFailure("sixgr:tests:ConformanceFRCContractFailed", ...
            "FRC contract-only setup validation failed.", ...
            preflightDiagnostics(setupFailures));
    end
    fprintf(1, [ ...
        'FRC contract-only profile completed: catalog and Tx TBS/G setup ' ...
        'contracts passed. No conformance, normative, statistical, or ' ...
        'symmetric +/-%.1f dB pass is asserted.\n'], opt.Tolerance_dB);
    ok = true;
    return;
end

preflightFailures = ~reshape([preflight.SetupPass], [], 1) | ...
    ~reshape([preflight.DataChannelExact], [], 1) | ...
    ~reshape([preflight.FullWaveformExact], [], 1);
if any(preflightFailures)
    disp(emptyReport);
    localThrowFailure("sixgr:tests:ConformanceFRCDataChannelExecutionBlocked", ...
        ["The real FRC gate did not start Monte Carlo because at least one " ...
        "mandatory complete-waveform point cannot yet be reproduced exactly. " ...
        "Every printed 'pass' value is therefore false."], ...
        preflightDiagnostics(preflightFailures));
end

numCases = height(mandatory);
results = cell(numCases, 1);
runDiagnostics = strings(numCases, 1);
for index = 1:numCases
    try
        results{index} = sixgr.conformance.runFRCPoint( ...
            mandatory.EntryId(index), mandatory.Condition(index), ...
            "ExecutionProfile", "full", ...
            "Tolerance_dB", opt.Tolerance_dB, ...
            "RequireExactStandardExecution", true, ...
            "RequireExactDataChannelExecution", true, ...
            "AssertPass", false, ...
            "PrintTable", false, ...
            "Verbose", opt.Verbose);
    catch cause
        runDiagnostics(index) = sprintf( ...
            "%s | %s: %s (%s)", ...
            mandatory.FRC(index), mandatory.Condition(index), ...
            string(cause.message), string(cause.identifier));
    end
end

[report, gatePass, resultDiagnostics] = ...
    localConsolidateResults(mandatory, results, runDiagnostics);
disp(report);

if any(~gatePass)
    localThrowFailure("sixgr:tests:ConformanceFRCGateFailed", ...
        ["Mandatory complete-waveform FRC reference gate failed. The standard " ...
        "defines a one-sided operating-point requirement; the +/-%.1f dB " ...
        "crossing is a separate, nonnormative simulator-regression gate. " ...
        "Measured and required deltas are listed below."], ...
        resultDiagnostics(~gatePass), opt.Tolerance_dB);
end

ok = true;
end

function opt = localParseOptions(varargin)
ip = inputParser;
ip.FunctionName = "testConformanceFRC";
ip.addParameter("Profile", "", @localTextScalar);
ip.addParameter("Tolerance_dB", 1.0, ...
    @(v) isnumeric(v) && isreal(v) && isscalar(v) && isfinite(v) && v > 0);
ip.addParameter("Verbose", true, @localLogicalScalar);
ip.parse(varargin{:});
opt = ip.Results;

profile = strtrim(lower(string(opt.Profile)));
if strlength(profile) == 0
    profile = strtrim(lower(string(getenv("SIXGR_FRC_TEST_PROFILE"))));
end
if strlength(profile) == 0
    profile = "gate";
end
profile = replace(profile, "_", "-");
if ~any(profile == ["gate", "contract-only"])
    error("sixgr:tests:InvalidConformanceFRCProfile", ...
        ["FRC test profile must be 'gate' or the explicit " ...
        "'contract-only' opt-in, not '%s'."], profile);
end
opt.Profile = profile;
opt.Tolerance_dB = double(opt.Tolerance_dB);
opt.Verbose = logical(opt.Verbose);
end

