function ok=testPDCCHRuntimeReceptionIntegrity()
% Main-caller structural guards; actual PHY behavior is exercised by the
% separate receive-boundary, noisy-stream and grant-gate waveform tests.
setup6GRSimToolkit('Verbose',false);
assert(nargin('sixgr.truth.runWaveformLinkBundle')==3);
source=fileread(which('sixgr.truth.runWaveformLinkBundle'));
control=fileread(which('sixgr.truth.PDCCHControlRuntime'));
complete=localBody(control,'function [r,receivedAssignment,channelEvidence] = receiveTrial(', ...
    'function [T, grant] = annotateGrant(');
receiveDelegate=localBody(source,'function varargout = localCompletePDCCHTrial(', ...
    'function varargout = localThermalNoiseSINRUnavailable(');
assert(contains(receiveDelegate, ...
    '[varargout{1:nargout}] = sixgr.truth.PDCCHControlRuntime.receiveTrial(varargin{:});') && ...
    ~contains(receiveDelegate,'completePDCCHReception('), ...
    'The coordinator must forward optional arguments and requested outputs to one receiver owner.');
shared=localBody(control,'function state=completeShared(', ...
    'function [state, qualifiedGrants, queuedGrants] = queueShared(');
assert(contains(source, ...
    'state=sixgr.truth.PDCCHControlRuntime.completeShared(state,item,@localAppendRuntimeLog);') && ...
    numel(strfind(shared,'sixgr.truth.PDCCHControlRuntime.receiveTrial('))==1 && ...
    numel(strfind(shared,'applyPDCCHGrantTrial('))==1 && ...
    numel(strfind(shared,'sixgr.truth.queueReceivedULGrantPreparation('))==1, ...
    'Shared completion must decode, reduce and hand off accepted UL control exactly once.');
for forbidden=["preparePDCCHTransmission(","localApplyPDCCHChannelAndNoise(", ...
        "applyCompositeReceiverFrontEnd(","initWaveformTruthChannelState(","rxNoise"]
    assert(~contains(complete,forbidden),'A received control reducer must not execute %s.',forbidden);
end
assert(contains(complete,'sixgr.link.completePDCCHReception(') && ...
    contains(complete,'sixgr.link.selectConnectedPDCCHDirection(rx,rxInfo,grantContext.Direction)') && ...
    contains(complete,'r.FalseAlarmFlag = double(r.PDCCHFalseAlarm)') && ...
    contains(complete,'r.NoiseFalseAlarmFlag = NaN') && ...
    contains(complete,'sixgr.truth.PDCCHControlRuntime.decodeObservedPDCCHGrantDCI('));
assert(contains(complete,'sixgr.link.buildPDCCHChannelEstimateTable(rx)') && ...
    contains(shared,'state.ControlTrials.PDCCHChannelEstimate=sixgr.truth.PDCCHControlRuntime.appendCompatTable(') && ...
    contains(source,'sixgr.report.exportPDCCHChannelEstimates('), ...
    'Receiver estimates must be captured, retained by shared completion and exported.');
independent=localBody(source,'function [T,H] = localCollectPDCCHTrialsAcrossSweep(', ...
    'function [T, correlationTraceT, raEvidenceTables] = localCollectPRACHTrialsAcrossSweep(');
collector=localBody(source,'function [T,updatedRuntimeChannelState,observedRET,allocatedRECoordinates,channelEstimates] = localCollectPDCCHTrials(', ...
    'function varargout = localCompletePDCCHTrial(');
assert(contains(independent,'[Ti,~,~,~,Hi]=localCollectPDCCHTrials(') && ...
    contains(independent,'bindComponentExecutionIdentity(Hi,cfg,"PDCCH")') && ...
    contains(collector,'[r,~,H]=localCompletePDCCHTrial(') && ...
    contains(collector,'H.TrialIndex=repmat(double(k),n,1)') && ...
    contains(source,'pdcchChannelEstimates,saveFigures)'), ...
    'Independent bundle must retain/export Hest from its own executed PDCCH trials.');
physical=localBody(source,'function [y,nVar,replay,updatedRuntimeChannelState] =', ...
    'function sampleRateHz = localResolvePDCCHSampleRate');
assert(numel(strfind(physical,'sixgr.link.applyCompositeReceiverFrontEnd('))==1 && ...
    ~contains(physical,'noiseOnly'),'Primary PDCCH must execute one actual receiver front end.');
assert(~contains(source,'localPDCCHPreAttachAssumptionApplies') && ...
    ~contains(source,'pre_attach_assumed_ok_no_trial_in_warmup') && ...
    ~contains(source,'legacy_addAwgnComplex_last_resort'));
template=fileread(which('sixgr.truth.makeLinkTrialRow'));
assert(contains(source,'[varargout{1:nargout}] = sixgr.truth.makeLinkTrialRow(varargin{:});') && ...
    ~contains(source,'row.PDCCHReceiverTrialExecuted = false;'), ...
    'Independent and shared collectors must delegate to one complete typed trial schema.');
for field=["PDCCHObservationStartSample","PDCCHObservationEndSampleExclusive", ...
        "PDCCHObservationCompletionTime_s","PDCCHMinimumReceiveSamples", ...
        "PDCCHDemodulatedSymbols","PDCCHReceivePaddingApplied"]
    assert(contains(complete,"r."+field+" =") && contains(template,"row."+field+" ="));
end
% The runtime assigns completion rows into a preallocated struct array.
% A producer-only field used to throw heterogeneousStrucAssignment after
% physical PDCCH reception, masking the actual receiver outcome.
produced=regexp(complete,'\br\.([A-Za-z]\w*)\s*=','tokens');
declared=regexp(template,'\brow\.([A-Za-z]\w*)\s*=','tokens');
produced=unique(string([produced{:}])); declared=unique(string([declared{:}]));
assert(all(ismember(produced,declared)), ...
    'PDCCH completion fields missing from preallocated schema: %s', ...
    strjoin(setdiff(produced,declared),', '));
assert(contains(template,'row.PDCCHReceiverTrialExecuted = false;') && ...
    contains(complete,'r.PDCCHReceiverTrialExecuted = true;'));
qualifier=localBody(source, ...
    'function [state, qualifiedGrants, queuedGrants] = localQualifyCoupledGrantsWithPDCCH(', ...
    'function state = localCollectCanonicalCoupledControlTrials(');
dispatch=strfind(qualifier,'sixgr.truth.PDCCHControlRuntime.queueShared(');
initialize=strfind(qualifier,'qualifiedGrants = repmat(struct(), 0, 1);');
assert(isscalar(dispatch) && isscalar(initialize) && dispatch<initialize && ...
    contains(regexprep(qualifier,'\s',''),'@localAppendRuntimeLog);return;') && ...
    ~contains(qualifier,'prepareSharedPDCCHTransmission(') && ...
    ~contains(qualifier,'SharedWaveformStream.queuePDCCH('), ...
    'Shared delegation must precede all grant/DAI/reservation mutations with no duplicate queued path.');
% Both runtime paths must distinguish candidate exhaustion from a failed
% received DCI. The native allocation test covers actual NoFreeCandidate;
% this guard covers the sequential caller's disposition and NDI rollback.
sequential=localBody(source, ...
    '    [pdcchRaw,pdcchUpdatedChannelState,pdcchObservedRET,allocatedControlREs] = localCollectPDCCHTrials(', ...
    '    if ~isempty(allocatedControlREs)');
assert(contains(sequential,'isempty(allocatedControlREs) && isempty(pdcchObservedRET)') && ...
    contains(sequential,'~pdcchRaw.PDCCHReceiverTrialExecuted') && ...
    contains(sequential,'blockPDCCHGrantTrial(state,grant,direction,reason)') && ...
    contains(sequential,"state,grant,direction,'DCINotIssued',true") && ...
    contains(sequential,'continue;'), ...
    'Sequential capacity deferral must not enter received-DCI failure or consume NDI.');
ok=true;
disp('PDCCH_RUNTIME_RECEPTION_INTEGRITY_STRUCTURE_PASS');
end

function body=localBody(source,first,last)
a=strfind(source,first); b=strfind(source,last);
assert(isscalar(a) && isscalar(b) && a<b);
body=source(a:b-1);
end
