function ok = testPDSCHReceiverNoNoiseExact()
%TESTPDSCHRECEIVERNONOISEEXACT Exact rank one through eight loopback.

setup6GRSimToolkit("Verbose", false);
totalCodewords = 0;
maxBitErrors = 0;
for rankValue = 1:8
    fixture = StrictPDSCHChainFixture.create(rankValue);
    tx = sixgr.pdsch.PDSCHTransmitter( ...
        fixture.TransportBlocks, fixture.Assignment, fixture.ResourcePlan, ...
        fixture.Carrier, fixture.ReferenceConfig, ...
        "PrecoderBundle", fixture.PrecoderBundle);
    rx = sixgr.pdsch.PDSCHReceiver( ...
        tx.Waveform, fixture.Assignment, fixture.ResourcePlan, ...
        fixture.Carrier, fixture.ReferenceConfig, fixture.ReceiverConfig, ...
        "CodingPlans", tx.CodingPlans, ...
        "PrecoderBundle", fixture.PrecoderBundle);
    assert(rx.CRCPass && all(rx.CRCPassPerCodeword), ...
        "Rank-%d no-noise strict receiver failed CRC.", rankValue);
    assert(numel(rx.TransportBlocks) == numel(fixture.TransportBlocks), ...
        "Rank-%d codeword count mismatch.", rankValue);
    for cw = 1:numel(fixture.TransportBlocks)
        errors = nnz(int8(rx.TransportBlocks{cw}(:)) ...
            ~= int8(fixture.TransportBlocks{cw}(:)));
        maxBitErrors = max(maxBitErrors, errors);
        assert(errors == 0, ...
            "Rank-%d codeword-%d exact TB mismatch.",rankValue,cw-1);
    end
    assert(size(rx.LayerSymbols,2) == rankValue ...
        && height(rx.DeprecoderTrace) ...
        == fixture.ResourcePlan.ExactDataRECount, ...
        "Rank-%d layer/deprecoder evidence mismatch.",rankValue);
    assert(all(rx.Metrics.DescrambledLLRCountPerCodeword ...
        == fixture.ResourcePlan.GPerCodeword), ...
        "Rank-%d LLR counts do not equal exact G.",rankValue);
    totalCodewords = totalCodewords + numel(fixture.TransportBlocks);
end

fprintf("PDSCH strict RX no-noise: ranks 1-8, %d codewords, max bit errors=%d\n", ...
    totalCodewords,maxBitErrors);
ok = true;
end
