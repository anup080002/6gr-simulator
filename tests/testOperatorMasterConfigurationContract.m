function ok = testOperatorMasterConfigurationContract()
%TESTOPERATORMASTERCONFIGURATIONCONTRACT Guard the two self-contained operator YAMLs.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

scenarioDir = fullfile(pwd, "simulator", "configs", "scenarios");
expectedFiles = sort([ ...
    "master_geometry_based.yaml"
    "master_sinr_sweep.yaml"]);
listed = dir(fullfile(scenarioDir, "master_*.yaml"));
actualFiles = sort(string({listed.name}).');
assert(isequal(actualFiles, expectedFiles), ...
    "The maintained operator surface must contain exactly %s; found %s.", ...
    strjoin(expectedFiles, ", "), strjoin(actualFiles, ", "));

tmp = string(tempname);
mkdir(tmp);
cleanup = onCleanup(@() localCleanup(tmp)); %#ok<NASGU>

fixed = localLoadAndBuild(scenarioDir, "master_sinr_sweep.yaml", ...
    "master_sinr_sweep", "fixed_snr_sweep_lls", ...
    "fixed_snr_sweep", tmp);
geometry = localLoadAndBuild(scenarioDir, "master_geometry_based.yaml", ...
    "master_geometry_based", "ue_placement_geometry_lls", ...
    "ue_placement_geometry", tmp);

localAssertModeDifferences(fixed, geometry);
localAssertMutationsPropagate(fixed.Raw, tmp);

ok = true;
end

function result = localLoadAndBuild(scenarioDir, fileName, scenarioID, ...
        runClass, scenarioMode, tmp)
path = fullfile(scenarioDir, fileName);
raw = sixgr.lls6g.config.readConfigFile(path);
assert(~isfield(raw, "inherits"), ...
    "%s must be self-contained and must not inherit another YAML.", fileName);
localAssertExplicitOperatorSurface(raw, fileName);

scfg = sixgr.lls6g.config.loadScenarioConfig(path);
assert(numel(scfg.SourceFiles) == 1, ...
    "%s must resolve from exactly one source file.", fileName);
assert(scfg.ScenarioID == scenarioID, ...
    "%s resolved the wrong scenario ID.", fileName);
assert(string(scfg.get("validation.run_class", "")) == runClass, ...
    "%s resolved the wrong run class.", fileName);
assert(string(sixgr.util.structGet(raw, ...
    "canonical_control.launch.scenario_mode", "")) == scenarioMode, ...
    "%s declares the wrong operator scenario mode.", fileName);

runFolder = fullfile(tmp, erase(fileName, ".yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scfg, runFolder);
assert(string(sixgr.util.structGet(cfg, "validation.RunClass", "")) == runClass, ...
    "%s did not preserve the YAML run class in the production config.", fileName);
localAssertBuiltSurface(raw, cfg, fileName);

result = struct("Raw", raw, "Resolved", scfg.toStruct(), "Cfg", cfg);
end

function localAssertExplicitOperatorSurface(raw, fileName)
