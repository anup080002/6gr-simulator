    "pdsch6gr.mcs_operating_band"
    "pdsch6gr.mcs_deployment_class"
    "pdsch6gr.mcs_frequency_range_allows_1024qam"
    "pdsch6gr.mcs_band_allows_1024qam"];
for index = 1:numel(requiredPaths)
    value = sixgr.util.structGet(raw, requiredPaths(index), []);
    assert(~isempty(value), "%s must explicitly configure %s.", ...
        fileName, requiredPaths(index));
end

carrier = raw.bwp.component_carriers;
assert(numel(carrier) == 1, ...
    "%s must explicitly configure one component carrier.", fileName);
localAssertEqual(double(carrier(1).dl_carrier_grid.n_size_grid), ...
    double(raw.canonical_control.radio.n_size_grid), ...
    fileName + " DL carrier grid");
localAssertEqual(double(carrier(1).ul_carrier_grid.n_size_grid), ...
    double(raw.canonical_control.radio.n_size_grid), ...
    fileName + " UL carrier grid");
end

function localAssertBuiltSurface(raw, cfg, fileName)
radio = raw.canonical_control.radio;
localAssertEqual(double(cfg.phy.carrier.NSizeGrid), ...
    double(radio.n_size_grid), fileName + " carrier grid");
localAssertEqual(double(cfg.phy.numerology.scs_kHz), ...
    double(radio.scs_khz), fileName + " numerology");
localAssertEqual(double(cfg.phy.bwp.dl.NStartBWP), ...
    double(raw.bwp.dl.n_start_bwp), fileName + " DL BWP start");
localAssertEqual(double(cfg.phy.bwp.dl.NSizeBWP), ...
    double(raw.bwp.dl.n_size_bwp), fileName + " DL BWP size");
localAssertEqual(double(cfg.phy.bwp.ul.NStartBWP), ...
    double(raw.bwp.ul.n_start_bwp), fileName + " UL BWP start");
localAssertEqual(double(cfg.phy.bwp.ul.NSizeBWP), ...
    double(raw.bwp.ul.n_size_bwp), fileName + " UL BWP size");
assert(~isempty(sixgr.util.structGet(cfg, ...
    "phy.frame.componentCarriers", [])), ...
    "%s did not attach the explicitly configured component carrier.", fileName);

localAssertAllocation(cfg.phy.pdsch, raw.pdsch, fileName + " PDSCH");
localAssertAllocation(cfg.phy.pusch, raw.pusch, fileName + " PUSCH");
localAssertEqual(double(cfg.phy.pdcch.SymbolAllocation), ...
    [double(raw.pdcch.start_symbol) double(raw.pdcch.num_symbols)], ...
    fileName + " PDCCH symbols");

timing = raw.tdd_timing;
localAssertEqual(double(cfg.phy.tddTiming.pdcchToPDSCHK0), ...
    double(timing.pdcch_to_pdsch_k0), fileName + " K0");
localAssertEqual(double(cfg.phy.tddTiming.dlHARQFeedbackK1Candidates), ...
    double(timing.dl_harq_feedback_k1), fileName + " K1");
localAssertEqual(double(cfg.phy.tddTiming.ulGrantK2), ...
    double(timing.ul_grant_k2), fileName + " K2");
policy = cfg.phy.frameStructure.TimingContext.Policy;
localAssertEqual(double(policy.SelectedK0), ...
    double(timing.pdcch_to_pdsch_k0), fileName + " frame policy K0");
localAssertEqual(double(policy.SelectedK1), ...
    double(timing.dl_harq_feedback_k1(1)), fileName + " frame policy K1");
localAssertEqual(double(policy.SelectedK2), ...
    double(timing.ul_grant_k2), fileName + " frame policy K2");

modulation = raw.canonical_control.modulation;
localAssertEqual(double(cfg.phy.pdsch.configuredMCSIndex), ...
    double(modulation.dl_mcs_index), fileName + " DL MCS");
localAssertEqual(double(cfg.phy.pusch.configuredMCSIndex), ...
    double(modulation.ul_mcs_index), fileName + " UL MCS");
assert(strcmpi(string(cfg.phy.pdsch.mcsTable), ...
    string(modulation.mcs_table)), ...
    "%s did not preserve the PDSCH MCS table.", fileName);
assert(strcmpi(string(cfg.phy.pusch.mcsTable), ...
    string(modulation.mcs_table)), ...
    "%s did not preserve the PUSCH MCS table.", fileName);
assert(strcmpi(string(cfg.phy.pdsch.executionProfile), ...
    string(raw.pdsch.execution_profile)), ...
    "%s did not preserve the PDSCH execution profile.", fileName);

context = cfg.phy.pdsch.mcsContext;
assert(logical(context.UECapability1024QAM) == ...
        logical(raw.pdsch6gr.mcs_ue_capability_1024qam) && ...
    logical(context.RRCEnabled1024QAM) == ...
        logical(raw.pdsch6gr.mcs_rrc_enabled_1024qam) && ...
    logical(context.DCIEnabled1024QAM) == ...
        logical(raw.pdsch6gr.mcs_dci_enabled_1024qam) && ...
    logical(context.DeploymentAllows1024QAM) == ...
        logical(raw.pdsch6gr.mcs_deployment_allows_1024qam) && ...
    strcmpi(string(context.FrequencyRange), ...
        string(raw.pdsch6gr.mcs_frequency_range)) && ...
    strcmpi(string(context.OperatingBand), ...
        string(raw.pdsch6gr.mcs_operating_band)) && ...
    strcmpi(string(context.DeploymentClass), ...
        string(raw.pdsch6gr.mcs_deployment_class)) && ...
    logical(context.FrequencyRangeAllows1024QAM) == ...
        logical(raw.pdsch6gr.mcs_frequency_range_allows_1024qam) && ...
    logical(context.BandAllows1024QAM) == ...
        logical(raw.pdsch6gr.mcs_band_allows_1024qam), ...
    "%s did not preserve the explicit PDSCH MCS capability context.", fileName);
end

function localAssertAllocation(actual, declared, label)
localAssertEqual(double(actual.SymbolAllocation), ...
    [double(declared.start_symbol) double(declared.num_symbols)], ...
    label + " symbols");
localAssertEqual(double(actual.prbStart), ...
    double(declared.prb_start), label + " PRB start");
localAssertEqual(double(actual.numPRB), ...
    double(declared.num_prb), label + " PRB count");
assert(strcmpi(string(actual.mappingType), string(declared.mapping_type)), ...
    "%s mapping type was not preserved.", label);
end

function localAssertModeDifferences(fixed, geometry)
assert(logical(fixed.Raw.canonical_control.launch.sweep_enabled) && ...
    ~logical(fixed.Raw.canonical_control.launch.geometry_enabled) && ...
    ~logical(geometry.Raw.canonical_control.launch.sweep_enabled) && ...
    logical(geometry.Raw.canonical_control.launch.geometry_enabled), ...
    "The two master YAMLs must expose distinct sweep and geometry modes.");
assert(double(fixed.Raw.canonical_control.topology.num_cells) == 1 && ...
    double(fixed.Raw.canonical_control.topology.num_ues) == 1 && ...
    double(geometry.Raw.canonical_control.topology.num_cells) == 2 && ...
    double(geometry.Raw.canonical_control.topology.num_ues) == 2, ...
    "The fixed and geometry masters must preserve their 1x1 and 2-cell/2-UE topology contracts.");
assert(strcmpi(string(fixed.Cfg.channel.model), "AWGN") && ...
    strcmpi(string(geometry.Cfg.channel.model), "CDL") && ...
    strcmpi(string(geometry.Cfg.channel.cdlProfile), "CDL-C"), ...
    "The fixed master must be AWGN and the geometry master must be concrete CDL-C.");
assert(~logical(fixed.Raw.canonical_control.harq.enabled) && ...
    logical(geometry.Raw.canonical_control.harq.enabled) && ...
    ~logical(fixed.Raw.canonical_control.random_access.enabled) && ...
    logical(geometry.Raw.canonical_control.random_access.enabled), ...
    "HARQ and random-access mode differences must remain explicit.");
assert(string(fixed.Cfg.phy.pdsch.executionProfile) == "phy_calibration" && ...
    string(geometry.Cfg.phy.pdsch.executionProfile) == "connected_strict", ...
    "Each mode must use its declared PDSCH production profile.");
assert(double(fixed.Cfg.phy.pdsch.numPRB) == 50 && ...
    double(geometry.Cfg.phy.pdsch.numPRB) == 273, ...
    "The two modes must retain their independently configured PDSCH allocations.");
end

function localAssertMutationsPropagate(raw, tmp)
raw.canonical_control.identity.scenario_id = ...
    "master_sinr_sweep_contract_mutation";
raw.bwp.dl.n_start_bwp = 5;
raw.bwp.dl.n_size_bwp = 260;
raw.bwp.ul.n_start_bwp = 7;
raw.bwp.ul.n_size_bwp = 250;
raw.pdsch.mapping_type = "B";
raw.pdsch.prb_start = 11;
raw.pdsch.num_prb = 23;
raw.pdsch.start_symbol = 3;
raw.pdsch.num_symbols = 10;
raw.pusch.mapping_type = "B";
raw.pusch.prb_start = 13;
raw.pusch.num_prb = 23;
raw.pusch.start_symbol = 1;
raw.pusch.num_symbols = 13;
raw.tdd_timing.pdcch_to_pdsch_k0 = 1;
raw.tdd_timing.pdcch_to_pusch_k2 = 2;
raw.tdd_timing.ul_grant_k2 = 2;
raw.canonical_control.modulation.dl_mcs_index = 10;
raw.canonical_control.modulation.ul_mcs_index = 10;
raw.pdsch6gr.fixed_mcs = 10;
raw.pdsch6gr.mcs_operating_band = "n78";
raw.validation.fixed_link_campaign.mcs = 10;
raw.validation.fixed_link_campaign.n_prb = 23;

path = fullfile(tmp, "mutated_master_sinr_sweep.yaml");
sixgr.util.jsonWrite(path, raw);
scfg = sixgr.lls6g.config.loadScenarioConfig(path);
cfg = sixgr.lls6g.buildInternalConfig(scfg, ...
    fullfile(tmp, "mutated_master_run"));

assert(scfg.ScenarioID == "master_sinr_sweep_contract_mutation");
localAssertBuiltSurface(raw, cfg, "mutated fixed master");
assert(double(cfg.phy.pdsch.configuredMCSIndex) == 10 && ...
    double(cfg.phy.pusch.configuredMCSIndex) == 10 && ...
    double(cfg.pdsch6gr.FixedMCS) == 10 && ...
    double(cfg.validation.fixed_link_campaign.mcs) == 10 && ...
    double(cfg.validation.fixed_link_campaign.n_prb) == 23 && ...
    strcmpi(string(cfg.phy.pdsch.mcsContext.OperatingBand), "n78"), ...
    "Mutated MCS values/capability context were bypassed by MATLAB defaults.");
assert(isequal(double(cfg.phy.pdsch.PRBSet), 11:33) && ...
    isequal(double(cfg.phy.pusch.PRBSet), 13:35), ...
    "Mutated YAML PRB allocations were bypassed by MATLAB defaults.");
end

function localAssertEqual(actual, expected, label)
assert(isequal(actual, expected), ...
    "%s mismatch: expected %s, got %s.", ...
    label, mat2str(expected), mat2str(actual));
end

function localCleanup(path)
if isfolder(path)
    rmdir(path, "s");
end
end
