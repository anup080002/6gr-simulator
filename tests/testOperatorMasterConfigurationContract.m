    "canonical_control.launch.scenario_mode"
    "canonical_control.run.noise_operating_mode"
    "canonical_control.topology.num_cells"
    "canonical_control.topology.num_ues"
    "canonical_control.radio.center_frequency_hz"
    "canonical_control.radio.bandwidth_hz"
    "canonical_control.radio.scs_khz"
    "canonical_control.radio.cp_type"
    "canonical_control.radio.duplex_mode"
    "canonical_control.radio.n_size_grid"
    "canonical_control.channel.model_type"
    "canonical_control.channel.profile"
    "canonical_control.modulation.dl_mcs_index"
    "canonical_control.modulation.ul_mcs_index"
    "canonical_control.modulation.mcs_table"
    "canonical_control.harq.enabled"
    "canonical_control.random_access.enabled"
    "bwp.dl.bwp_id"
    "bwp.dl.n_start_bwp"
    "bwp.dl.n_size_bwp"
    "bwp.dl.scs_khz"
    "bwp.ul.bwp_id"
    "bwp.ul.n_start_bwp"
    "bwp.ul.n_size_bwp"
    "bwp.ul.scs_khz"
    "bwp.component_carriers"
    "pdsch.execution_profile"
    "pdsch.mapping_type"
    "pdsch.prb_start"
    "pdsch.num_prb"
    "pdsch.start_symbol"
    "pdsch.num_symbols"
    "pusch.mapping_type"
    "pusch.prb_start"
    "pusch.num_prb"
    "pusch.start_symbol"
    "pusch.num_symbols"
    "pdcch.start_symbol"
    "pdcch.num_symbols"
    "tdd_timing.pdcch_to_pdsch_k0"
    "tdd_timing.pdcch_to_pusch_k2"
    "tdd_timing.dl_harq_feedback_k1"
    "tdd_timing.ul_grant_k2"
    "tdd_timing.n1_pdsch_processing_time_symbols"
    "tdd_timing.n2_pusch_preparation_time_symbols"
    "tdd_timing.capability_profile_id"
