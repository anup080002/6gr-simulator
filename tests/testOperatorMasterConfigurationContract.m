    "pdsch6gr.fixed_mcs"
    "pdsch6gr.mcs_ue_capability_1024qam"
    "pdsch6gr.mcs_rrc_enabled_1024qam"
    "pdsch6gr.mcs_dci_enabled_1024qam"
    "pdsch6gr.mcs_deployment_allows_1024qam"
