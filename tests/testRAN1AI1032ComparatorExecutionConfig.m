function ok=testRAN1AI1032ComparatorExecutionConfig()
%TESTRAN1AI1032COMPARATOREXECUTIONCONFIG Bind YAML maps to real PHY MCS.
setup6GRSimToolkit('Verbose',false);
files=["c0_fixed.yaml";"c1_fixed.yaml";"c2a_fixed.yaml"; ...
    "study.yaml";"c4_fixed.yaml";"c5_fixed.yaml"];
ids=["C0";"C1";"C2a";"C3";"C4";"C5"];
b27Indices=[27;22;27;27;22;55]; h0Indices=[NaN;23;28;32;23;64];
for k=1:numel(files)
    path="configs/tdoc/ai_10_3_2_modulation/"+files(k);
    [study,provenance]=sixgr.studies.ran1ai1032.loadStudyConfig(path);
    assert(upper(string(study.lls.execution.representation_id))==upper(ids(k)) && ...
        strlength(string(provenance.ConfigSHA256))==64 && ...
        numel(provenance.SourceFiles)==1+double(k~=4), ...
        'Comparator YAML inheritance or resolved provenance is wrong.');
    plan=sixgr.studies.ran1ai1032.buildLLSCasePlan(study);
    row=plan.CasePlan(plan.CasePlan.ExperimentID=="F1" & ...
        plan.CasePlan.EntryID=="B27" & ...
        plan.CasePlan.ChannelProfile=="AWGN" & ...
        plan.CasePlan.AntennaCaseID=="simo_1x4_r1",:);
    cfg=sixgr.studies.ran1ai1032.buildF1RuntimeConfig(study,row,30,1032+k);
    assert(cfg.phy.pusch.mcsIndex==b27Indices(k) && ...
        string(cfg.phy.pusch.mcsTable)==string(study.lls.execution.mcs_table) && ...
        cfg.phy.pusch.codeRate==948/1024, ...
        'B27 physical rate or local index changed in comparator execution.');
    if ~isnan(h0Indices(k))
        row=plan.CasePlan(plan.CasePlan.ExperimentID=="F1" & ...
            plan.CasePlan.EntryID=="H0" & ...
            plan.CasePlan.ChannelProfile=="AWGN" & ...
            plan.CasePlan.AntennaCaseID=="simo_1x4_r1",:);
        cfg=sixgr.studies.ran1ai1032.buildF1RuntimeConfig(study,row,30,2032+k);
        assert(cfg.phy.pusch.mcsIndex==h0Indices(k) && ...
            cfg.phy.pusch.codeRate==805.5/1024, ...
            'H0 physical rate or local index changed in comparator execution.');
    end
end
ok=true;
fprintf('RAN1_AI1032_COMPARATOR_EXECUTION_CONFIG_PASS maps=%d\n',numel(files));
end
