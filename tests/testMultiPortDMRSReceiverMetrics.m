function ok = testMultiPortDMRSReceiverMetrics()
%TESTMULTIPORTDMRSRECEIVERMETRICS Port-aware, receiver-only DM-RS metrics.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
rng(73, "twister");
ranks = [2 3 4 8];
for rankValue = ranks
    [carrier, pdsch] = localConfig(rankValue);
    refInd = nrPDSCHDMRSIndices(carrier, pdsch);
    refSym = nrPDSCHDMRS(carrier, pdsch);
    [rxGrid, hEst] = localReceivedReferenceGrid( ...
        carrier, refInd, refSym, rankValue);

    clean = sixgr.phy.rx.referenceSignalMetrics( ...
        rxGrid, hEst, refInd, refSym, ...
        "NoiseVariance", 1e-8, ...
        "ContextLabel", "rank" + string(rankValue) + "_clean");
    impairedGrid = localPerturbPhysicalReferenceRE( ...
        rxGrid, clean.PhysicalLinearIndices, 0.08);
    impaired = sixgr.phy.rx.referenceSignalMetrics( ...
        impairedGrid, hEst, refInd, refSym, ...
        "NoiseVariance", 1e-8, ...
        "ContextLabel", "rank" + string(rankValue) + "_impaired");

    assert(clean.ReferencePortCount == rankValue ...
        && clean.PhysicalRECount == numel(unique(mod( ...
        double(refInd(:)) - 1, size(rxGrid,1) * size(rxGrid,2)) + 1)), ...
        "Rank-%d reference metrics lost the physical RE/port geometry.", ...
        rankValue);
    assert(isfinite(clean.NMSEdB) && clean.NMSEdB < -120 ...
        && isfinite(clean.SINRdB), ...
        "Rank-%d clean reconstruction must be finite and near exact.", ...
        rankValue);
    assert(isfinite(impaired.NMSEdB) ...
        && impaired.NMSEdB > clean.NMSEdB + 40 ...
        && impaired.SINRdB < clean.SINRdB, ...
        "Rank-%d metric must respond to controlled received-pilot error.", ...
        rankValue);
    assert(string(clean.ValueRole) == ...
        "dmrs_pilot_reconstruction_residual_without_true_channel_oracle", ...
        "Receiver metric must disclose its non-oracle measurement role.");

    cfg = localCSIConfig(rankValue);
    csiClean = sixgr.phy.dl.CSI_Feedback(hEst, 1e-8, cfg, ...
        "Direction", "DL", ...
        "ReceivedGrid", rxGrid, ...
        "ReferenceIndices", refInd, ...
        "ReferenceSymbols", refSym);
    csiImpaired = sixgr.phy.dl.CSI_Feedback(hEst, 1e-8, cfg, ...
        "Direction", "DL", ...
        "ReceivedGrid", impairedGrid, ...
        "ReferenceIndices", refInd, ...
        "ReferenceSymbols", refSym);
    assert(isfinite(double(csiClean.PilotSINR_dB)) ...
        && isfinite(double(csiClean.ReferencePilotNMSE_dB)) ...
        && isfinite(double(csiImpaired.PilotSINR_dB)) ...
        && isfinite(double(csiImpaired.ReferencePilotNMSE_dB)), ...
        "Rank-%d CSI feedback must expose finite receiver-derived metrics.", ...
        rankValue);
    assert(abs(double(csiClean.PilotSINR_dB) - clean.SINRdB) < 1e-9 ...
        && abs(double(csiImpaired.ReferencePilotNMSE_dB) ...
        - impaired.NMSEdB) < 1e-9 ...
        && double(csiImpaired.PilotSINR_dB) ...
        < double(csiClean.PilotSINR_dB), ...
        "Rank-%d CSI feedback did not consume the port-aware metric.", ...
        rankValue);
end

ok = true;
fprintf("Multi-port DM-RS metrics: ranks 2/3/4/8 finite, port-aware, perturbation-sensitive PASS\n");
end

function [carrier, pdsch] = localConfig(rankValue)
carrier = nrCarrierConfig;
carrier.NSizeGrid = 12;
carrier.SubcarrierSpacing = 30;
pdsch = nrPDSCHConfig;
pdsch.PRBSet = 0:5;
pdsch.SymbolAllocation = [0 14];
pdsch.MappingType = "A";
if rankValue > 4
    pdsch.Modulation = {"QPSK","QPSK"};
else
    pdsch.Modulation = "QPSK";
end
pdsch.NumLayers = rankValue;
pdsch.DMRS.DMRSTypeAPosition = 2;
pdsch.DMRS.DMRSConfigurationType = 1;
pdsch.DMRS.DMRSAdditionalPosition = 1;
pdsch.DMRS.DMRSLength = 1 + double(rankValue > 4);
pdsch.DMRS.NumCDMGroupsWithoutData = 2;
pdsch.DMRS.DMRSPortSet = 0:(rankValue - 1);
end

function [rxGrid, hEst] = localReceivedReferenceGrid( ...
        carrier, refInd, refSym, rankValue)
K = double(carrier.NSizeGrid) * 12;
L = double(carrier.SymbolsPerSlot);
R = rankValue;
P = rankValue;
H = (randn(R,P) + 1j * randn(R,P)) ./ sqrt(2 * P);
hEst = repmat(reshape(H, [1 1 R P]), K, L, 1, 1);
rxFlat = complex(zeros(K * L, R));
indices = double(refInd(:));
symbols = double(refSym(:));
physical = mod(indices - 1, K * L) + 1;
ports = floor((indices - 1) ./ (K * L)) + 1;
hFlat = reshape(hEst, K * L, R, P);
for i = 1:numel(indices)
    rxFlat(physical(i), :) = rxFlat(physical(i), :) ...
        + hFlat(physical(i), :, ports(i)) .* symbols(i);
end
rxGrid = reshape(rxFlat, K, L, R);
end

function output = localPerturbPhysicalReferenceRE(input, physical, amplitude)
output = input;
flat = reshape(output, size(output,1) * size(output,2), ...
    max(1, size(output,3)));
phase = reshape(1:(numel(physical) * size(flat,2)), ...
    numel(physical), size(flat,2));
perturbation = double(amplitude) .* exp(1j .* phase ./ 7);
flat(double(physical(:)), :) = flat(double(physical(:)), :) ...
    + perturbation;
output = reshape(flat, size(output));
end

function cfg = localCSIConfig(rankValue)
cfg = sixgr.config.defaultConfig();
cfg.channel.nTxAnt = rankValue;
cfg.channel.nRxAnt = rankValue;
cfg.phy.nTxAnt = rankValue;
cfg.phy.nRxAnt = rankValue;
cfg.phy.pdsch.nLayers = rankValue;
cfg.phy.pdsch.numLayers = rankValue;
cfg.phy.csi.maxRank = rankValue;
% This test covers receiver reconstruction for arbitrary rank/port counts,
% including the valid rank-3 data case.  A three-port Type-I dual-polarized
% CSI codebook is not a valid NR codebook geometry, so keep this diagnostic
% on the explicitly declared non-codebook SVD receiver.
cfg.phy.csi.pmiCodebookMode = "noncodebook";
cfg.phy.csi.codebookType = "noncodebook";
cfg.phy.csi.maxTrustedReferenceSINR_dB = 300;
cfg.phy.csi.reportCQI = true;
cfg.phy.csi.reportPMI = true;
cfg.phy.csi.reportRI = true;
end
