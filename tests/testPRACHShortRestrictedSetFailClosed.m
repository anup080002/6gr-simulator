function ok = testPRACHShortRestrictedSetFailClosed()
%TESTPRACHSHORTRESTRICTEDSETFAILCLOSED Strict short-format PRACH guard.
%
% The focused PRACH campaign format uses MATLAB-style flat field names.
% PRACHConfig must consume those values and reject restricted sets before
% Toolbox occasion enumeration can mask the semantic error.

setup6GRSimToolkit("Verbose", false);

scenario = struct( ...
    "ScenarioName", "short_restricted_set_regression", ...
    "CarrierFrequencyHz", 4e9, ...
    "DuplexMode", "TDD", ...
    "CarrierSCSkHz", 30, ...
    "NSizeGrid", 273, ...
    "PRACHConfigurationIndex", 87, ...
    "PRACHSubcarrierSpacing", 15, ...
    "PRACHFormat", "A2", ...
    "ZeroCorrelationZone", 8, ...
    "ChannelModel", "AWGN");

failedClosed = false;
try
    sixgr.rach.PRACHConfig(scenario, ...
        "RestrictedSet", "RestrictedSetTypeA");
catch ME
    failedClosed = strcmp(string(ME.identifier), ...
        "sixgr:rach:PRACHConfig:RestrictedSetInvalidForShortFormat");
end
assert(failedClosed, ...
    "Short-format PRACH with a restricted set must fail with the canonical typed validation error.");

ok = true;
fprintf("PASS testPRACHShortRestrictedSetFailClosed: flat-field A2 authority and typed restricted-set rejection verified.\n");
end
