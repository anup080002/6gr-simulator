function ok=testMeasuredSINRIntervalBoundaries()
% Numerical export fixtures, not decoded PHY or statistical qualification.
% A zero/all-error Wilson interval includes the exact observed endpoint.
setup6GRSimToolkit('Verbose',false,'RunToolboxChecks',false);
for n=[11 1 37]
    for errors=unique([0 floor(n/2) n])
        crc=[zeros(errors,1);ones(n-errors,1)];
        trial=table((1:n).',repmat(21.5,n,1),repmat("OK",n,1), ...
            crc,true(n,1),false(n,1),false(n,1), ...
            'VariableNames',{'Slot','PostEqSINR_dB','PostEqSINRValueStatus', ...
            'CRCPass','FinalizedFlag','IsWarmupFrame','FallbackFlag'});
        root=tempname; mkdir(root);
        cleanup=onCleanup(@()rmdir(root,'s'));
        out=sixgr.analytics.generateMeasuredSINRCurves(root,'interval_fixture', ...
            'TrialData',struct('dl',trial,'ul',trial), ...
            'ScenarioConfig',struct('global_radio_scope', ...
            struct('channel_bandwidth_hz',5e6)), ...
            'WriteKPISummary',false,'UpdateAnchorKPIs',false);
        mobility=sixgr.analytics.buildMobilityAdequacyReport( ...
            struct('frame',struct('scs_khz',15)),trial,root);
        reference=sixgr.validation.BinomialIntervalEngine.wilson(errors,n,.95);
        assert(mobility.DLFailCount==errors && mobility.DLPassCount==n-errors && ...
            mobility.DL_BLER==errors/n && ...
            mobility.DL_BLER_CI95_Low<=mobility.DL_BLER && ...
            mobility.DL_BLER<=mobility.DL_BLER_CI95_High && ...
            abs(mobility.DL_BLER_CI95_Low-reference.Lower)<1e-14 && ...
            abs(mobility.DL_BLER_CI95_High-reference.Upper)<1e-14, ...
            'testMeasuredSINRIntervalBoundaries:MobilityEndpointExcluded', ...
            'The mobility report must preserve counts and use the same exact interval endpoints.');
        assert(~mobility.OverallAdequate && mobility.HonestLabel=="SHORT_OR_SPARSE_DIAGNOSTIC", ...
            'Correcting interval arithmetic must not qualify a sparse diagnostic population.');
        for direction=["DL","UL"]
            curve=out.Tables.(direction+"BlerCurve");
            assert(height(curve)==1 && curve.TrialCount==n && ...
                curve.FailureCount==errors && curve.BLER==errors/n);
            assert(0<=curve.BLER_CI_Low && curve.BLER_CI_Low<=curve.BLER && ...
                curve.BLER<=curve.BLER_CI_High && curve.BLER_CI_High<=1, ...
                'testMeasuredSINRIntervalBoundaries:EndpointExcluded', ...
                'The exact observed binomial proportion must lie inside its Wilson interval.');
            reference=sixgr.validation.BinomialIntervalEngine.wilson(errors,n,.95);
            assert(abs(curve.BLER_CI_Low-reference.Lower)<1e-14 && ...
                abs(curve.BLER_CI_High-reference.Upper)<1e-14, ...
                'Measured-SINR exports must use the canonical 95-percent Wilson implementation.');
            persisted=readtable(out.Paths.(direction+"BlerCurve"), ...
                'VariableNamingRule','preserve');
            assert(persisted.BLER_CI_Low<=persisted.BLER && ...
                persisted.BLER<=persisted.BLER_CI_High);
            if errors==0, assert(persisted.BLER_CI_Low==0); end
            if errors==n, assert(persisted.BLER_CI_High==1); end
        end
        clear cleanup;
    end
end
fprintf('MEASURED_SINR_INTERVAL_BOUNDARIES_PASS DL/UL numerical CSV fixtures only\n');
ok=true;
end
