function ok = testIndependentCSIRSTransmissionPreparation()
%TESTINDEPENDENTCSIRSTRANSMISSIONPREPARATION Exact 5 MHz cell-common TX.
setup6GRSimToolkit("Verbose", false);
scenario = sixgr.lls6g.config.loadScenarioConfig( ...
    "simulator/configs/scenarios/lls_tdd_5mhz_rank2_4tx2rx_awgn_m10db.yaml");
cfg = sixgr.lls6g.buildInternalConfig(scenario, tempname);

% The retained run's configured calendar contains slot 32.  Preparation is
% cell-common and cannot consume a PDSCH grant, DCI result or HARQ state.
prepared = sixgr.link.prepareCSIRSTransmission( ...
    cfg, -10, "RuntimeSlot", 32);
carrier = prepared.Carrier;
assert(carrier.NSizeGrid == 25 && size(prepared.Tx.Grid,3) == 4 && ...
    size(prepared.TransmitSamples,2) == 4, ...
    'test:IndependentCSIRSPhysicalDimensions', ...
    'The 5 MHz 4x2 scenario must transmit CSI-RS on four gNB waveform dimensions.');
assert(prepared.Tx.CSIRSRuntimeEvent.Scheduled && ...
    prepared.Tx.CSIRSRuntimeEvent.Transmitted && ...
    prepared.RFExecutionDeferred && prepared.ChannelExecutionDeferred, ...
    'test:IndependentCSIRSPreparationStage', ...
    'Preparation must retain real CSI-RS IQ while deferring RF/channel execution.');
indices = prepared.Tx.CSIRSRuntimeEvent.WaveformIndices;
symbols = prepared.Tx.CSIRSRuntimeEvent.WaveformSymbols;
assert(~isempty(indices) && numel(indices) == numel(symbols) && ...
    all(prepared.Tx.Grid(indices) == symbols) && ...
    all(prepared.Tx.Grid(setdiff((1:numel(prepared.Tx.Grid)).', indices)) == 0), ...
    'test:IndependentCSIRSExactGrid', ...
    'Standalone CSI-RS must contain only the configured physical reference REs.');
assert(string(prepared.ReferenceIdentity.Source) == ...
    "configured_periodic_cell_common_csirs_physical_grid" && ...
    strlength(string(prepared.ReferenceIdentity.PhysicalGridDigest)) == 64, ...
    'test:IndependentCSIRSIdentity', ...
    'Retain immutable physical grid and calendar identity before shared execution.');
assert(string(prepared.PowerContext.WaveformAmplitudeUnit) == "sqrt_mW" && ...
    isfinite(prepared.PowerContext.OutputTotalPower_dBm), ...
    'test:IndependentCSIRSPowerContext', ...
    'Standalone CSI-RS must use the same physical power-context contract as data.');

localAssertThrows(@() sixgr.link.prepareCSIRSTransmission( ...
    cfg, -10, "RuntimeSlot", 33), ...
    "sixgr:link:CSIRSPreparationOutsideOccasion");

poison = cfg;
poison.phy.pdsch.nLayers = 99;
poison.phy.pdsch.mcsIndex = 28;
poison.phy.pdsch.RNTI = 65535;
again = sixgr.link.prepareCSIRSTransmission( ...
    poison, -10, "RuntimeSlot", 32);
assert(isequaln(prepared.Tx.Grid, again.Tx.Grid) && ...
    prepared.ReferenceIdentity.PhysicalGridDigest == ...
        again.ReferenceIdentity.PhysicalGridDigest, ...
    'test:IndependentCSIRSNoPDSCHDependency', ...
    'CSI-RS transmission must not depend on PDSCH rank, MCS, RNTI or DCI state.');

% Exercise the same producer on the requested 400 MHz numerology.  This is
% a PHY-grid capability check, not acceptance of the currently disabled
% full 400 MHz shared-feedback scenario.
cfg400 = cfg;
cfg400.phy.carrier.SubcarrierSpacing = 120;
cfg400.phy.carrier.NSizeGrid = 264;
cfg400.phy.csirs.numRB = 264;
cfg400.phy.csirs.numRBsByResource = 264;
prepared400 = sixgr.link.prepareCSIRSTransmission( ...
    cfg400, 30, "RuntimeSlot", 32);
ofdm400 = nrOFDMInfo(prepared400.Carrier);
assert(ofdm400.Nfft == 4096 && ofdm400.SampleRate == 491.52e6 && ...
    size(prepared400.TransmitSamples,2) == 4 && ...
    prepared400.Tx.CSIRSRuntimeEvent.Transmitted, ...
    'test:IndependentCSIRS400MHzGrid', ...
    'The independent CSI-RS producer must retain the 4096-FFT/491.52 MHz four-port grid.');
fprintf(['INDEPENDENT_CSIRS_TX_PREPARATION_PASS slot=32 PRB=%d ' ...
    'waveform_ports=%d NRE=%d fs=%g 400MHz_NRE=%d\n'], carrier.NSizeGrid, ...
    size(prepared.TransmitSamples,2), numel(indices), prepared.SampleRateHz, ...
    numel(prepared400.Tx.CSIRSRuntimeEvent.WaveformIndices));
ok = true;
end

function localAssertThrows(fh, expectedIdentifier)
try
    fh();
catch cause
    assert(strcmp(cause.identifier, expectedIdentifier), ...
        'Expected %s, received %s: %s', expectedIdentifier, ...
        cause.identifier, cause.message);
    return;
end
error('testIndependentCSIRSTransmissionPreparation:MissingFailure', ...
    'Expected %s.', expectedIdentifier);
end
