function ok = testSRSRuntimeCanonicalWidebandResource()
setup6GRSimToolkit("Verbose", false);

scenarioPath = fullfile("simulator", "configs", "scenarios", "master_geometry_based.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, tempname);

cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.run.noiseOperatingMode = "standalone_awgn_snr_argument";

slotIndex = 10;
out = sixgr.link.runSRSChannelEstimation(cfg, "SNR_dB", 35, "SlotIndex", slotIndex);

assert(logical(out.Ok), "Runtime SRS channel-estimation path must execute successfully.");
assert(logical(out.MeasurementUsable), "Runtime SRS must produce a usable measured CSI row.");
assert(isfinite(double(out.SRSOccupiedPRBCount)) && isfinite(double(out.SRSCarrierPRBCount)), ...
    "Runtime SRS must export finite mapped/carrier PRB counts.");
assert(double(out.SRSOccupiedPRBCount) >= double(out.SRSCarrierPRBCount) - 1, ...
    "Runtime SRS must use the canonical wideband SRS resource, not the 4-PRB Toolbox default.");
assert(double(out.SRSBandwidthFraction) >= 0.99, ...
    "Runtime SRS wideband fraction must be sufficient for the SRS CSI freshness gate.");
assert(string(out.SRSBandwidthCoverageStatus) == "full_carrier", ...
    sprintf(['A requested 273-RB SRS resolved to the standardized 272-RB mapping must ' ...
        'be classified as full_carrier under the explicit one-edge-RB tolerance. ' ...
        'Observed status=%s occupied=%g carrier=%g fraction=%g.'], ...
        char(string(out.SRSBandwidthCoverageStatus)), ...
        double(out.SRSOccupiedPRBCount), double(out.SRSCarrierPRBCount), ...
        double(out.SRSBandwidthFraction)));
assert(isfinite(double(out.SINR_dB)) && string(out.SINRValueStatus) == "OK", ...
    "Runtime SRS must produce finite receiver SINR for CSI/AMC consumption.");
assert(contains(string(out.NoiseVarianceSource), ...
        "standalone_awgn_measured_received_occupied_grid_esn0_reference") && ...
    ~logical(out.WaveformPowerUsedForAWGN), ...
    "Standalone SRS AWGN must use received occupied-RE Es/N0, never sparse-waveform average power.");
expectedGridNoise = double(out.SignalEnergyPerOccupiedRE) .* 10^(-35/10);
assert(isfinite(expectedGridNoise) && expectedGridNoise > 0 && ...
    abs(double(out.ReferenceAWGNGridNoiseVariance) - expectedGridNoise) <= ...
        max(1e-12, expectedGridNoise * 1e-10), ...
    "SRS grid-noise variance must preserve Es/N0 after the exact runtime channel and power scales.");
assert(abs(double(out.AppliedNoiseSNR_dB) - 35) <= 1e-10, ...
    "SRS exported AWGN reference SNR must close exactly at the requested occupied-RE Es/N0.");
assert(strlength(strtrim(string(out.SINRMeasurementDomain))) > 0 && ...
    strlength(strtrim(string(out.PowerReferencePlane))) > 0, ...
    "Runtime SRS receiver SINR must identify its measurement domain and reference plane.");
assert(startsWith(string(out.SpatialSignatureSource), ...
        "measured_srs_receiver_channel_estimate"), ...
    ["The SRS producer must classify its measured pilot-RE spatial signature " ...
     "with the canonical receiver-channel-estimate source prefix consumed by " ...
     "the causal MU scheduler."]);

ok = true;
end
