function ok = testPDSCHDMRSEPREDifference()
%TESTPDSCHDMRSEPREDIFFERENCE Verify configurable PDSCH DM-RS EPRE scaling.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
if ~localHaveRequired5G()
    warning("testPDSCHDMRSEPREDifference:Missing5G", ...
        "Skipping PDSCH DM-RS EPRE test because required 5G Toolbox APIs are unavailable.");
    ok = true;
    return;
end

rng(381014, "twister");
cfgDefault = localCfg();
W = eye(4);
[txDefault, infoDefault] = sixgr.phy.dl.PDSCH_Tx(cfgDefault, ...
    "PrecodingMatrix", W, "CompactOutput", false);
[~, nominalDMRS] = sixgr.phy.refsig.dmrsPDSCH(txDefault.Carrier, txDefault.PDSCH);

assert(abs(double(txDefault.DMRSDataToDMRSEPREDifference_dB)) < 1e-12 && ...
        abs(double(txDefault.DMRSAmplitudeScale) - 1) < 1e-12 && ...
        ~logical(txDefault.DMRSEPREDifference.Applied), ...
    "Missing PDSCH DM-RS EPRE config must preserve the historical 0 dB default.");
assert(localMaxAbs(txDefault.DMRSSymbols - nominalDMRS) < 1e-12, ...
    "The default PDSCH DM-RS symbols must remain identical to the toolbox reference.");
assert(abs(double(infoDefault.DMRS.DMRSAmplitudeScale) - 1) < 1e-12, ...
    "PDSCH Tx info must disclose the default unit DM-RS scale.");

cfgBoost = cfgDefault;
cfgBoost.phy.pdsch.dmrs.dataToDMRSEPREDifference_dB = -3;
expectedScale = sqrt(2);
expectedRealizedBoost_dB = 10 * log10(2);
[txBoost, infoBoost] = sixgr.phy.dl.PDSCH_Tx(cfgBoost, ...
    "Carrier", txDefault.Carrier, ...
    "PDSCH", txDefault.PDSCH, ...
    "TransportBlockBits", txDefault.TransportBlock, ...
    "TransportBlockSizeOverride", txDefault.TransportBlockSize, ...
    "TargetCodeRate", txDefault.TargetCodeRate, ...
    "RV", txDefault.RV, ...
    "PrecodingMatrix", W, ...
    "CompactOutput", false);

assert(abs(double(txBoost.DMRSDataToDMRSEPREDifference_dB) + 3) < 1e-12 && ...
        abs(double(txBoost.DMRSConfiguredPowerBoost_dB) - 3) < 1e-12 && ...
        abs(double(txBoost.DMRSPowerBoost_dB) - expectedRealizedBoost_dB) < 1e-12 && ...
        abs(double(txBoost.DMRSAmplitudeScale) - expectedScale) < 1e-12 && ...
        logical(txBoost.DMRSEPREDifference.Applied) && ...
        logical(txBoost.DMRSEPREDifference.NormativeMinus3dBBetaApplied), ...
    "The normative -3 dB token must apply exact beta=sqrt(2) and disclose configured versus realized dB.");
assert(localMaxAbs(txBoost.DMRSSymbols - nominalDMRS .* expectedScale) < 1e-12, ...
    "PDSCH Tx must scale every logical-layer DM-RS symbol by the configured amplitude.");
assert(localMaxAbs(txBoost.PDSCHLayerSymbols - txDefault.PDSCHLayerSymbols) < 1e-12, ...
    "PDSCH DM-RS EPRE scaling must not change PDSCH data symbols.");
assert(abs(double(infoBoost.DMRSEPREDifference.DMRSPowerScale) - 2) < 1e-12, ...
    "PDSCH Tx info must disclose the exact realized DM-RS power scale.");
assert(string(infoBoost.DMRSEPREDifference.ScalePolicy) == ...
        "normative_minus3_db_beta_sqrt2", ...
    "The normative -3 dB scale policy must be explicit in PDSCH Tx provenance.");
assert(string(txBoost.TxContext.DMRSEPREDifference.Source) == ...
        "phy.pdsch.dmrs.dataToDMRSEPREDifference_dB", ...
    "PDSCH TxContext must retain the resolved DM-RS EPRE config source.");
localAssertMappedDMRS(txBoost);

[rxBoost, rxInfo] = sixgr.phy.dl.PDSCH_Rx(txBoost.Waveform, cfgBoost, ...
    "Carrier", txBoost.Carrier, ...
    "PDSCH", txBoost.PDSCH, ...
    "PDSCHIndices", txBoost.PDSCHIndices, ...
    "TransportBlockSize", txBoost.TransportBlockSize, ...
    "TargetCodeRate", txBoost.TargetCodeRate, ...
    "RV", txBoost.RV, ...
    "CodingPlan", txBoost.CodingPlans, ...
    "NoiseVar", 1e-9, ...
    "NoiseVarDomain", "grid", ...
    "CodingLayout", txBoost.CodingLayout, ...
    "PrecodingMatrix", W, ...
    "CompactOutput", false, ...
    "SkipTimingEstimate", true);

assert(logical(rxBoost.Ok) && ~logical(rxBoost.CRCError), ...
    "Matched boosted-DMRS rank-4 PDSCH must decode in the near-noiseless identity channel.");
assert(all(int8(rxBoost.TransportBlock(:)) == int8(txBoost.TransportBlock(:))), ...
    "Matched boosted-DMRS PDSCH must recover the transmitted transport block.");
assert(localMaxAbs(rxBoost.DMRSSymbols - txBoost.DMRSSymbols) < 1e-12, ...
    "PDSCH Tx and Rx must use the same boosted DM-RS reference.");
assert(abs(double(rxBoost.DMRSAmplitudeScale) - expectedScale) < 1e-12 && ...
        abs(double(rxInfo.DMRS.DMRSAmplitudeScale) - expectedScale) < 1e-12, ...
    "PDSCH Rx outputs must disclose the configured DM-RS scale.");

pilotH = nrExtractResources(txBoost.DMRSIndices, rxBoost.ChannelEstimate);
pilotH = pilotH(isfinite(real(pilotH)) & isfinite(imag(pilotH)));
activePilotH = abs(double(pilotH));
activePilotH = activePilotH(activePilotH > 0.25);
assert(~isempty(activePilotH) && abs(median(activePilotH) - 1) < 2e-2, ...
    "Matched boosted DM-RS references must preserve a unit identity-channel estimate.");

localAssertInvalidDifferenceRejected(cfgDefault);

fprintf("PDSCHDMRSEPREDifference: rank-4 0 dB default, exact -3 dB boost, grid mapping, and matched Rx verified.\n");
ok = true;
end

function localAssertMappedDMRS(tx)
ind = tx.DMRSAntennaIndices;
sym = tx.DMRSAntennaSymbols;
assert(numel(ind) == numel(sym), ...
    "PDSCH mapped DM-RS indices and symbols must have equal cardinality.");
mapped = tx.Grid(ind(:));
assert(localMaxAbs(mapped(:) - sym(:)) < 1e-12, ...
    "The waveform resource grid must contain the boosted PDSCH DM-RS symbols.");
end

function localAssertInvalidDifferenceRejected(cfg)
cfg.phy.pdsch.dmrs.dataToDMRSEPREDifference_dB = NaN;
thrown = false;
try
    sixgr.phy.dl.PDSCH_Tx(cfg, "PrecodingMatrix", eye(4), "CompactOutput", true);
catch ME
    thrown = strcmp(ME.identifier, "sixgr:phy:dl:PDSCHDMRSEPREDifferenceInvalid");
end
assert(thrown, "A non-finite PDSCH data-to-DMRS EPRE difference must fail loudly.");
end

