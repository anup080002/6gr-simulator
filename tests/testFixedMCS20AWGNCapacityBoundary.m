function ok = testFixedMCS20AWGNCapacityBoundary()
%TESTFIXEDMCS20AWGNCAPACITYBOUNDARY Explain the fixed-MCS waterfall scope.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
context = struct( ...
    "UECapability1024QAM", false, ...
    "RRCEnabled1024QAM", false, ...
    "DCIEnabled1024QAM", false, ...
    "DeploymentAllows1024QAM", false, ...
    "FrequencyRangeAllows1024QAM", false, ...
    "BandAllows1024QAM", false, ...
    "FrequencyRange", "FR1", ...
    "OperatingBand", "n77", ...
    "DeploymentClass", "macro", ...
    "DCIFormat", "1_1");
profile = sixgr.pdsch.PDSCHMCSResolver.resolve( ...
    "qam256_table2", 20, context);

assert(profile.Qm == 8 && string(profile.Modulation) == "256QAM", ...
    "MCS 20 in the configured table must resolve to 256QAM.");
assert(abs(profile.TargetCodeRate - 682.5/1024) < 1e-14 && ...
    abs(profile.SpectralEfficiency - 5.3320) < 1e-12, ...
    "MCS 20 must retain its normative target rate and spectral efficiency.");

capacity10 = log2(1 + 10^(10/10));
capacity20 = log2(1 + 10^(20/10));
assert(capacity10 < profile.SpectralEfficiency && ...
    capacity20 > profile.SpectralEfficiency, ...
    ["The ideal AWGN capacity bound must explain why fixed MCS 20 is " ...
    "unsupported at 10 dB but becomes feasible before 20 dB."]);

fprintf("FixedMCS20AWGNCapacityBoundary: MCS20 SE=%.4f, C10=%.4f, C20=%.4f PASS\n", ...
    profile.SpectralEfficiency, capacity10, capacity20);
ok = true;
end
