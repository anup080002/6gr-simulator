function ok = testTDDMultiNumerologyExpansion()
%TESTTDDMULTINUMEROLOGYEXPANSION Prove exact reference-to-active expansion.

setup6GRSimToolkit("Verbose", false);
p = struct("PeriodicityMilliseconds", 5, ...
    "NumDownlinkSlots", 6, "NumDownlinkSymbols", 4, ...
    "NumUplinkSlots", 3, "NumUplinkSymbols", 2);
reference = sixgr.phy.frame.TDDCommonConfig.resolve( ...
    "ReferenceSubcarrierSpacingKHz", 30, ...
    "ActiveSubcarrierSpacingKHz", 30, ...
    "Pattern1", p);
active = sixgr.phy.frame.TDDCommonConfig.resolve( ...
    "ReferenceSubcarrierSpacingKHz", 30, ...
    "ActiveSubcarrierSpacingKHz", 60, ...
    "Pattern1", p);

expectedFlat = repelem(reshape(reference.CommonDirection.', 1, []), 2);
actualFlat = reshape(active.CommonDirection.', 1, []);
assert(isequal(actualFlat, expectedFlat), ...
    "30-to-60 kHz TDD mapping must expand every reference symbol exactly.");
assert(active.ActiveSlotsPerPattern == 20);
assert(active.SymbolsPerSlot == 14);
assert(active.PatternDurationMilliseconds == 5);
assert(~any(active.CommonDirection == 'F' & ...
    active.ResolvedDirection ~= "UNRESOLVED_FLEX", "all"));

% Dedicated slot indices are reference-SCS slots and expand without
% selecting only the first active-SCS slot.
allFlexPattern = struct("PeriodicityMilliseconds", 0.5, ...
    "NumDownlinkSlots", 0, "NumDownlinkSymbols", 0, ...
    "NumUplinkSlots", 0, "NumUplinkSymbols", 0);
allFlex = sixgr.phy.frame.TDDCommonConfig.resolve( ...
    "ReferenceSubcarrierSpacingKHz", 30, ...
    "ActiveSubcarrierSpacingKHz", 60, "Pattern1", allFlexPattern);
dedicated = sixgr.phy.frame.TDDDedicatedConfig.apply(allFlex, ...
    struct("SlotIndex", 0, "Mode", "explicit", ...
    "FirstDownlinkSymbols", 1, "LastUplinkSymbols", 1));
flat = reshape(dedicated.SymbolDirection.', 1, []);
assert(isequal(flat(1:2), 'DD') && isequal(flat(end-1:end), 'UU'));
assert(all(flat(3:end-2) == 'F'));

% A repeated 5 ms pattern is continuous at both 10 ms frame boundaries.
assert(isequal(active.directionsForFrame(0), active.directionsForFrame(1)));
assert(isequal(active.directionsForFrame(1), active.directionsForFrame(2)));

% Positive 0.625 ms is an exact five-slot cycle at 120 kHz.
shortPattern = struct("PeriodicityMilliseconds", 0.625, ...
    "NumDownlinkSlots", 2, "NumDownlinkSymbols", 3, ...
    "NumUplinkSlots", 2, "NumUplinkSymbols", 2);
short = sixgr.phy.frame.TDDCommonConfig.resolve( ...
    "ReferenceSubcarrierSpacingKHz", 120, ...
    "ActiveSubcarrierSpacingKHz", 120, ...
    "Pattern1", shortPattern);
assert(short.ActiveSlotsPerPattern == 5 && ...
    short.PatternDurationMilliseconds == 0.625);
shortBoundary = short.directionsAtAbsoluteSlots([79, 80]);
assert(all(shortBoundary(1, :) == 'U') && ...
    all(shortBoundary(2, :) == 'D'));

% Two positive 1.25 ms patterns expand from the 60 kHz reference grid to
% the 120 kHz active BWP.  Verify the complete P1+P2 symbol stream and a
% distant frame boundary rather than sampling one slot.
p1 = struct("PeriodicityMilliseconds", 1.25, ...
    "NumDownlinkSlots", 2, "NumDownlinkSymbols", 4, ...
    "NumUplinkSlots", 2, "NumUplinkSymbols", 2);
p2 = struct("PeriodicityMilliseconds", 1.25, ...
    "NumDownlinkSlots", 1, "NumDownlinkSymbols", 0, ...
    "NumUplinkSlots", 3, "NumUplinkSymbols", 0);
referenceP1 = sixgr.phy.frame.TDDCommonConfig.resolve( ...
    "ReferenceSubcarrierSpacingKHz", 60, ...
    "ActiveSubcarrierSpacingKHz", 60, ...
    "Pattern1", p1, "Pattern2", p2);
activeP1 = sixgr.phy.frame.TDDCommonConfig.resolve( ...
    "ReferenceSubcarrierSpacingKHz", 60, ...
    "ActiveSubcarrierSpacingKHz", 120, ...
    "Pattern1", p1, "Pattern2", p2);
expectedP1 = repelem( ...
    reshape(referenceP1.CommonDirection.', 1, []), 2);
assert(isequal(reshape(activeP1.CommonDirection.', 1, []), expectedP1));
assert(activeP1.ActiveSlotsPerPattern == 20 && ...
    activeP1.PatternDurationMilliseconds == 2.5);
pairedBoundary = activeP1.directionsAtAbsoluteSlots([79, 80]);
assert(all(pairedBoundary(1, :) == 'U') && ...
    all(pairedBoundary(2, :) == 'D'));
assert(isequal(activeP1.directionsForFrame(0), ...
    activeP1.directionsForFrame(10000)));

localAssertError(@() sixgr.phy.frame.TDDCommonConfig.resolve( ...
    "ReferenceSubcarrierSpacingKHz", 120, ...
    "ActiveSubcarrierSpacingKHz", 30, "Pattern1", p), ...
    "sixgr:phy:frame:ReferenceSCSExceedsActiveBWPSCS");
ok = true;
end

function localAssertError(f, id)
try
    f();
catch ME
    assert(string(ME.identifier) == string(id), ...
        "Observed %s, expected %s.", ME.identifier, id);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", "Expected %s.", id);
end
