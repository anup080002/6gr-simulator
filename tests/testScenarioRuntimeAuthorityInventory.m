function ok = testScenarioRuntimeAuthorityInventory()
%TESTSCENARIORUNTIMEAUTHORITYINVENTORY Fail closed on study/runtime confusion.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
root = fileparts(fileparts(mfilename("fullpath")));
scenarioPath = fullfile(root, "simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring.yaml");
outputRoot = tempname;
mkdir(outputRoot);
cleanup = onCleanup(@() localCleanup(outputRoot)); %#ok<NASGU>

out = sixgr.analytics.buildScenarioRuntimeAuthorityInventory( ...
    scenarioPath, outputRoot, root);
F = out.FileTable;
G = out.GateTable;
assert(out.PreRunAuthorityPass && logical(G.PreRunAuthorityPass), ...
    "The causal scenario has a missing or misclassified runtime owner.");
assert(double(G.RequiredRuntimeOwnerCount) >= 35, ...
    "The scenario runtime authority surface is unexpectedly small.");
assert(double(G.RequiredOwnerFailureCount) == 0 && ...
    double(G.MissingRequiredOwnerCount) == 0 && ...
    double(G.MisclassifiedRequiredOwnerCount) == 0, ...
    "Required runtime owners must exist and remain production-authoritative.");
assert(height(out.FunctionTable) >= 16000, ...
    "The function-level authority inventory is incomplete.");

required = F(F.RequiredForScenario, :);
assert(all(required.FileExists & required.AuthorityAllowed & ...
    required.PreRunPass), ...
    "Every required owner must exist and be runtime/reporting eligible.");
assert(~any(contains(lower(required.FilePath), ["/+tdoc/","/+c0/+campaigns/"])) && ...
    ~any(contains(required.RuntimeEligibility, ["ISOLATED","OFFLINE", ...
    "ORACLE","VALIDATION","LEGACY"])), ...
    "A study, TDoc, oracle, validation, or legacy owner leaked into runtime.");

mustOwn = ["+sixgr/+phy/+dl/PDSCH_Tx.m", ...
    "+sixgr/+phy/+dl/PDSCH_Rx.m", ...
    "+sixgr/+phy/+ul/PUSCH_Tx.m", ...
    "+sixgr/+phy/+ul/PUSCH_Rx.m", ...
    "+sixgr/+phy/+frame/FrameRuntimeStateBuilder.m", ...
    "+sixgr/+phy/+broadcast/recoverSIB1FromWaveform.m", ...
    "+sixgr/+phy/+frame/PRACHOccasionResolver.m", ...
    "+sixgr/+truth/CoupledTruthRuntime.m"];
paths = string(required.FilePath);
assert(all(ismember(mustOwn, paths)), ...
    "A mandatory access-to-data production owner is absent.");
assert(any(F.Category == "ISOLATED_STUDY_OR_VALIDATION") && ...
    all(~F.RequiredForScenario(F.Category == ...
    "ISOLATED_STUDY_OR_VALIDATION")), ...
    "Study/validation files must remain visible but non-authoritative.");
assert(isfile(out.FileInventoryPath) && isfile(out.FunctionInventoryPath) && ...
    isfile(out.GatePath), "Runtime authority CSV artifacts are missing.");

ok = true;
fprintf("[PASS] scenario runtime authority: %d required owners, %d files, %d functions, zero study leaks.\n", ...
    double(G.RequiredRuntimeOwnerCount), height(F), height(out.FunctionTable));
end

function localCleanup(folder)
if isfolder(folder)
    rmdir(folder, "s");
end
end
