function ok=testInitialNRMACReset()
% Actual codec/timer/HARQ owners; physical retirement is an explicit input.
% This verifies the reset transaction, not an executed shared-stream T300.
[~,f]=testNRRRCSetupAttemptState();
a=f.WaitingAttempt;expired=f.ExpiredAttempt;expiry=f.Expiry;
state=struct('SharedWaveformStream',struct('Events',struct('NextSampleIndex',expiry.ExpirySample)), ...
    'NumUsers',2,'MultiUser',struct('RNTIStart',321), ...
    'CurrentServingIdx',[1 1],'NRRRCSetupAttemptsByUE',{{a,[]}}, ...
    'AccessState',["initial_access","connected"], ...
    'TimeAlignmentState',["not_established","aligned"], ...
    'PendingRAAttempts',{{[],struct('Peer',true)}}, ...
    'RARetryByUE',{{struct('OriginalAttempt',"MAC_attempt_3"),struct('Peer',true)}}, ...
    'ConnectedULTimingByUE',{{struct('PendingInitialTiming',true),struct('Peer',true)}}, ...
    'SharedUEULPowerControlStates',{{struct('InitialPower',true),struct('Peer',true)}}, ...
    'UEConfiguredSRProcedures',{{struct('InitialSR',true);struct('Peer',true)}}, ...
    'LastTimingAdvanceSamplesByUE',[3 7], 'LastTimingAdvanceUsByUE',[.1 .2], ...
    'LastTimingAdvanceEffectiveAtSampleByUE',[4000 5000], ...
    'LastTimingAdvanceSourceByUE',["initial","peer"], ...
    'TimingAdvanceUpdateRequiredByUE',[false false], ...
    'TimingAdvanceUpdateStatusByUE',["initial","peer"], ...
    'UECommonCellConfigurationByUE',{{f.OriginalCommon,struct('Peer',true)}});
for direction=["DL","UL"]
    h=sixgr.l2.mac.HARQEntity(struct(),'Direction',direction,'NumProcesses',2);
    reserved=h.allocate(321,1,100);
    assert(h.cancelTentativeTx(321,reserved.HARQ.HarqID,'DCINotIssued',true));
    peer=h.allocate(322,2,100);g=peerGrant(direction,peer.HARQ);
    h.onTx(322,peer.HARQ.HarqID,uint8(zeros(800,1)),g,2);
    h.storeSoftBuffer(322,peer.HARQ.HarqID,struct('LLRSum',[1;2;3],'ObservationWeight',1));
    state.(direction+"Harq")=h;
end
peerDL=state.DLHarq.UEProcs{state.DLHarq.UEList==322};
peerUL=state.ULHarq.UEProcs{state.ULHarq.UEList==322};
originalSI=state.UECommonCellConfigurationByUE;
dlHistory=state.DLHarq.DeliveryLedger;ulHistory=state.ULHarq.DeliveryLedger;
plan=sixgr.truth.prepareInitialNRMACReset(state,1,expiry);
assert(numel(plan.HARQOwners)==2 && all(plan.HARQRNTIs==321));
assert(isequaln(peerDL,state.DLHarq.UEProcs{state.DLHarq.UEList==322}));
bad=state;bad.SharedWaveformStream.Events.NextSampleIndex=expiry.ExpirySample+1;
reject(@()sixgr.truth.prepareInitialNRMACReset(bad,1,expiry),'sixgr:truth:NRRRCInitialReset');
bad=state;bad.NRSRB1RuntimeByUE={struct('ExistingBearer',true),[]};
reject(@()sixgr.truth.prepareInitialNRMACReset(bad,1,expiry),'sixgr:truth:NRRRCReestablishmentNotIntegrated');
bad=state;bad.RadioIdentityBindings=struct('UEIndex',2,'ServingCell',1,'RNTI',321);
reject(@()sixgr.truth.prepareInitialNRMACReset(bad,1,expiry),'sixgr:truth:NRRRCResetPeerIdentityCollision');
bad=state;bad.RadioIdentityBindings=struct('UEIndex',1,'ServingCell',1,'RNTI',4660);
reject(@()sixgr.truth.prepareInitialNRMACReset(bad,1,expiry),'sixgr:truth:NRRRCInitialReset');
retirement=struct('ContractVersion',"initial_NR_access_physical_retirement/v1", ...
    'OriginalTimerID',"DECLARED_T300_RETIREMENT_COMPONENT_INPUT",'UEIndex',1, ...
    'ResetSample',expiry.ExpirySample,'SampleRateHz',a.Context.SampleRateHz, ...
    'ClockEpoch',a.Context.ConfigurationEpoch,'AttemptRunIDs',a.MACAttemptRunIDs, ...
    'Callbacks',struct([]),'Cancellations',{{}},'EmittedSamplesChanged',false, ...
    'GNBCellResponsesCancelled',false);
retirement.SHA256=string(sixgr.util.sha256Hex(jsonencode(retirement)));
after=sixgr.truth.commitInitialNRMACReset(state,1,expired,plan,retirement);
assert(after.AccessState(1)=="failed_T300" && after.AccessState(2)==state.AccessState(2));
assert(after.NRRRCSetupAttemptsByUE{1}.Status=="failed_upper_layer_notified" && ...
    isempty(after.PendingRAAttempts{1}) && isempty(after.RARetryByUE{1}) && ...
    isempty(after.ConnectedULTimingByUE{1}) && isempty(after.SharedUEULPowerControlStates{1}) && ...
    isempty(after.UEConfiguredSRProcedures{1}) && isnan(after.LastTimingAdvanceSamplesByUE(1)));
assert(isequaln(originalSI,after.UECommonCellConfigurationByUE) && ...
    isequaln(peerDL,after.DLHarq.UEProcs{after.DLHarq.UEList==322}) && ...
    isequaln(peerUL,after.ULHarq.UEProcs{after.ULHarq.UEList==322}) && ...
    isequaln(dlHistory,after.DLHarq.DeliveryLedger) && isequaln(ulHistory,after.ULHarq.DeliveryLedger));
assert(isequaln(after.PendingRAAttempts{2},state.PendingRAAttempts{2}) && ...
    isequaln(after.RARetryByUE{2},state.RARetryByUE{2}) && ...
    isequaln(after.UEConfiguredSRProcedures{2},state.UEConfiguredSRProcedures{2}));
r=after.NRRRCUpperLayerIndications{1};
assert(r.ApplicationBytesDropped==0 && r.ReceivedSystemInformationPreserved && ...
    ~r.GNBCellResponsesCancelled && numel(r.HARQResetReceipts)==2 && ...
    after.RetiredInitialNRRAAttempts{1}.OriginalOwners.RARetryByUE.OriginalAttempt=="MAC_attempt_3");
reject(@()after.NRRRCSetupAttemptsByUE{1}.resetCompleted(r),'sixgr:rrc:InitialAttemptAuthority');
bad=r;bad.RequestSHA256=string(repmat('f',1,64));
reject(@()expired.resetCompleted(bad),'sixgr:rrc:InitialAttemptAuthority');
bad=r;bad.SHA256="missing_original_receipt";
reject(@()expired.resetCompleted(bad),'sixgr:rrc:InitialAttemptAuthority');
% Full original callback structs survive ordering, with no synthesized row.
kinds=["RRCSetupExpiry","BindSRSPower","RARExpiry","Contention","Msg1TX","SRS","PUSCH"];
items=struct('ID',num2cell(1:numel(kinds)),'Kind',cellstr(kinds));
ordered=sixgr.truth.orderSharedReceiverCompletions(items);
assert(isequal(string({ordered.Kind}),["Msg1TX","SRS","PUSCH","RARExpiry","Contention","RRCSetupExpiry","BindSRSPower"]));
assert(isequal(sort([ordered.ID]),1:numel(kinds)));
% A fabricated timer cannot enter the production physical retirement owner.
owner=sixgr.truth.CoupledWaveformStream();
reject(@()owner.validateOriginalRRCSetupExpiry(struct('Kind',"RRCSetupExpiry")), ...
    'sixgr:truth:NRRRCInitialReset');
ok=true;
fprintf('INITIAL_NR_MAC_RESET_PASS twoUE_scope=1 original_SI_and_peer_HARQ_preserved=1 exact_clock_order=1 physical_retirement_declared=1 RF=0\n');
end
function g=peerGrant(direction,h)
layout=sixgr.phy.phycode.resolveCodingLayout('Direction',direction,'TransportBlockSize',800, ...
    'TargetCodeRate',.3,'RV',0,'Modulation','QPSK','NumLayers',1,'RateMatchedBitCount',2748);
g=struct('TBSBits',800,'Direction',direction,'Modulation','QPSK','NumLayers',1, ...
    'TargetCodeRate',.3,'CodingLayout',layout,'HARQ',h,'TransportBlockId',direction+"_peer_original");
end
function reject(f,id)
try,f();catch e,assert(string(e.identifier)==id,'Expected %s, got %s: %s',id,e.identifier,e.message);return;end
error('test:InitialResetGuardMissing','Expected %s.',id);
end
