function ok = testConfiguredPhysicalAntennaMetadata()
%TESTCONFIGUREDPHYSICALANTENNAMETADATA Keep elements, ports and layers distinct.

setup6GRSimToolkit("Verbose", false);

cfg = struct();
cfg.antenna.bs.numElements = 64;
cfg.antenna.bs.numPorts = 32;
cfg.antenna.ue.numElements = 4;
cfg.antenna.ue.numPorts = 4;
cfg.scenario.bs.nTxAnt = 64;
cfg.scenario.bs.nRxAnt = 64;
cfg.scenario.ue.nTxAnt = 4;
cfg.scenario.ue.nRxAnt = 4;

ul = table(4, 4, 4, 64, 2, 2, ...
    'VariableNames', { ...
    'ConfiguredTxAntennas','ConfiguredRxAntennas', ...
    'UEAntennaElements','BSAntennaElements', ...
    'NumRxAntennas','Layers'});
ul = sixgr.truth.canonicalizeConfiguredPhysicalAntennaMetadata( ...
    ul, cfg, "UL");
assert(double(ul.ConfiguredTxAntennas) == 4 && ...
    double(ul.ConfiguredRxAntennas) == 64, ...
    "UL configured antenna metadata must describe the 4-element UE transmitter and 64-element gNB receiver.");
assert(double(ul.NumRxAntennas) == 2 && double(ul.Layers) == 2, ...
    "Physical metadata repair must not rewrite post-combining branches or decoded layers.");

dl = table(32, 4, 64, 4, ...
    'VariableNames', { ...
    'ConfiguredTxAntennas','ConfiguredRxAntennas', ...
    'BSAntennaElements','UEAntennaElements'});
dl = sixgr.truth.canonicalizeConfiguredPhysicalAntennaMetadata( ...
    dl, cfg, "DL");
assert(double(dl.ConfiguredTxAntennas) == 64 && ...
    double(dl.ConfiguredRxAntennas) == 4, ...
    "DL configured antenna metadata must describe the 64-element gNB transmitter and 4-element UE receiver.");

fallback = table(NaN, NaN, ...
    'VariableNames', {'ConfiguredTxAntennas','ConfiguredRxAntennas'});
fallback = sixgr.truth.canonicalizeConfiguredPhysicalAntennaMetadata( ...
    fallback, cfg, "UL");
assert(double(fallback.ConfiguredTxAntennas) == 4 && ...
    double(fallback.ConfiguredRxAntennas) == 64, ...
    "Resolved YAML physical element counts must be the fallback authority when row-level antenna metadata is absent.");

ok = true;
end
