function localAssertIdentifier(fn, expected, requiredMessage)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(expected), ...
        "Expected %s but received %s: %s", expected, ME.identifier, ME.message);
    assert(contains(string(ME.message), string(requiredMessage)), ...
        "Strict failure must preserve the typed producer's physical blocker.");
    return;
end
error("sixgr:test:ExpectedErrorNotRaised", ...
    "Expected error %s was not raised.", expected);
end
