function ok = testPUSCHMeasuredReferencePowerControl()
%TESTPUSCHMEASUREDREFERENCEPOWERCONTROL Validate the live PUSCH power plane.

% The exercised production path must consume a causally measured
% reference-signal pathloss, evaluate TS 38.213 power control, and let
% sixgr.rf.applyPowerContext perform the only physical waveform scaling.

setup6GRSimToolkit("Verbose", false);
localValidateCausalPathlossSelector();
localValidateReferenceResourceIdentity();
localValidateYAMLPathlossReferenceAuthority();
cfg = localConfig();
out = sixgr.link.runULPUSCHThroughput(cfg, ...
    "NumFrames", 1, "SNR_dB", 30, "ExecutionProfile", "phy_calibration");
assert(istable(out.TrialTable) && height(out.TrialTable) == 1, ...
    "The focused production PUSCH run must emit one truthful trial row.");
row = out.TrialTable(1,:);
required = ["PUSCHPowerControlEnabled","PUSCHPowerControlStatus", ...
    "PUSCHTxPower_dBm","PUSCHRequestedPower_dBm", ...
    "PUSCHMeasuredWaveformPower_dBm","PUSCHPowerClosureError_dB", ...
    "PUSCHPowerClipped","PUSCHPowerHeadroom_dB", ...
    "PUSCHPowerControlPathloss_dB","PUSCHPathlossReferenceRS", ...
    "PUSCHPowerControlSource","PUSCHPowerAmplitudeScale", ...
    "CellTotalTxPower_dBm","EndpointPowerBudget_dBm", ...
    "ConcurrentTransmitterGrantCount","GrantPowerFraction", ...
    "GrantTargetTxPower_dBm","ScheduledPowerPolicy", ...
    "ScheduledPowerAuthority","SharedCellBudgetApplied"];
assert(all(ismember(required, string(row.Properties.VariableNames))), ...
    "Canonical PUSCH trials must expose the measured power-control ledger.");

mu = 1; % 30 kHz SCS
mrb = 6;
expectedRequested = -80 + 10 * log10((2 ^ mu) * mrb) + 0.8 * 100;
assert(logical(row.PUSCHPowerControlEnabled) && ...
    string(row.PUSCHPowerControlStatus) == ...
    "resolved_ts_38_213_exact_single_power_context_scaling");
assert(abs(double(row.PUSCHRequestedPower_dBm) - expectedRequested) < 1e-9, ...
    "PUSCH requested power must implement the TS 38.213 mu/MRB formula.");
assert(abs(double(row.PUSCHTxPower_dBm) - expectedRequested) < 1e-9 && ...
    ~logical(row.PUSCHPowerClipped), ...
    "The unclipped applied PUSCH power must equal the exact request.");
assert(abs(double(row.PUSCHPowerHeadroom_dB) - (23 - expectedRequested)) < 1e-9, ...
    "PHR must be PCMAX minus requested power, including any negative headroom.");
assert(abs(double(row.PUSCHMeasuredWaveformPower_dBm) - ...
    expectedRequested) < 1e-8 && ...
    abs(double(row.PUSCHPowerClosureError_dB)) < 1e-8, ...
    "The exact waveform must be scaled once and close to the controller output.");
assert(abs(double(row.PUSCHPowerControlPathloss_dB) - 100) < 1e-12 && ...
    string(row.PUSCHPathlossReferenceRS) == "CSI-RS-0" && ...
    contains(string(row.PUSCHPowerControlSource), ...
    "exact_waveform_csirs_tx_rx_reference_re_difference"), ...
    "PUSCH power control must preserve measured RS pathloss provenance.");
assert(isnan(double(row.CellTotalTxPower_dBm)) && ...
    abs(double(row.EndpointPowerBudget_dBm) - 23) < 1e-12 && ...
    double(row.ConcurrentTransmitterGrantCount) == 1 && ...
    abs(double(row.GrantPowerFraction) - 1) < 1e-12 && ...
    abs(double(row.GrantTargetTxPower_dBm) - expectedRequested) < 1e-9 && ...
    string(row.ScheduledPowerPolicy) == ...
        "ts_38_213_pusch_power_control_per_ue_transmitter" && ...
    contains(string(row.ScheduledPowerAuthority), ...
        "exact_waveform_csirs_tx_rx_reference_re_difference") && ...
    ~logical(row.SharedCellBudgetApplied), ...
    ["PUSCH schedule evidence must distinguish UE PCMAX from the exact " ...
     "TS 38.213 power applied to the transmitted grant."]);

badCfg = cfg;
badCfg.lls6g.userContext.RuntimeServingPathlossSource = ...
    "configured_snr_pathloss_proxy";
localAssertIdentifier(@() sixgr.link.runULPUSCHThroughput(badCfg, ...
    "NumFrames", 1, "SNR_dB", 30, "ExecutionProfile", "phy_calibration"), ...
    "sixgr:link:StrictCoverageUnsupported", ...
    "PUSCH power control rejected pathloss source");

missingCfg = cfg;
if isfield(missingCfg.phy.pusch.powerControl, "p0UE_dB")
    missingCfg.phy.pusch.powerControl = rmfield( ...
        missingCfg.phy.pusch.powerControl, "p0UE_dB");
end
if isfield(missingCfg.phy.pusch, "power_control") && ...
        isfield(missingCfg.phy.pusch.power_control, "p0_ue_db")
    missingCfg.phy.pusch.power_control = rmfield( ...
        missingCfg.phy.pusch.power_control, "p0_ue_db");
end
localAssertIdentifier(@() sixgr.link.runULPUSCHThroughput(missingCfg, ...
    "NumFrames", 1, "SNR_dB", 30, "ExecutionProfile", "phy_calibration"), ...
    "sixgr:link:StrictCoverageUnsupported", ...
    "explicit P0-PUSCH, P0-UE, and alpha");

ok = true;
fprintf("[PASS] testPUSCHMeasuredReferencePowerControl exact request %.6f dBm.\n", ...
    expectedRequested);
end

function localValidateReferenceResourceIdentity()
% A newer observation from another SSB beam must not satisfy power control
% for the YAML-selected SSB resource.  Resource identity is part of the
% physical measurement key, not a display-only label.
T = table( ...
    ["SSB";"SSB"], ["UE";"UE"], [1;1], [4;5], [4;5], ...
    [true;true], [0;1], [-118;-75], [82;39], ...
    ["SSB_UE_1_resource_0_slot_4";"SSB_UE_1_resource_1_slot_5"], ...
    ["SSB-0";"SSB-1"], ...
    ["exact_generated_tx_sss_epre_minus_ue_measured_noise_debiased_ss_rsrp"; ...
     "exact_generated_tx_sss_epre_minus_ue_measured_noise_debiased_ss_rsrp"], ...
    'VariableNames', ["SignalType","TargetType","TargetId", ...
    "ProducerSlot","AvailableSlot","Valid","ResourceId", ...
    "RSRP_dBm","Pathloss_dB","MeasurementId", ...
    "PathlossReferenceRS","PathlossSource"]);
state = struct("ReferenceSignalMeasurementTable", T, "SweepPointStartSlot", 1);
selected = sixgr.truth.CoupledTruthRuntime.consumeReferenceSignalPathlossRuntime( ...
    state, "SSB", "UE", 1, 6, 20, 0);
assert(logical(selected.Usable) && double(selected.ProducerSlot) == 4 && ...
    double(selected.SelectedRow.ResourceId) == 0 && ...
    double(selected.SelectedRow.Pathloss_dB) == 82, ...
    "Power control must consume the configured SSB resource, not a newer different beam.");
end

function localValidateCausalPathlossSelector()
% A later valid CSI feedback row without absolute reference powers must not
% shadow the physical CSI-RS Tx/Rx pathloss observation from the same slot.
T = table( ...
    ["CSI-RS";"CSI-RS"], ["UE";"UE"], [1;1], [12;12], [12;13], ...
    [true;true], ["DL";"DL"], ["CSI-RS";"CSI-RS"], ...
    ["CSI-RS_UE_1_slot_12";"CSI-RS_UE_1_slot_12"], ...
    ["physical_csirs_measurement";"delayed_csi_feedback"], ...
    [86.5;NaN], ["CSI-RS-resource-0";"CSI-RS"], ...
    ["exact_tx_csirs_epre_minus_ue_measured_csirs_rsrp";""], ...
    'VariableNames', ["SignalType","TargetType","TargetId", ...
    "ProducerSlot","AvailableSlot","Valid","Direction","SourceSignal", ...
    "MeasurementId","MeasurementSource","Pathloss_dB", ...
    "PathlossReferenceRS","PathlossSource"]);
state = struct("ReferenceSignalMeasurementTable", T, "SweepPointStartSlot", 1);
selected = sixgr.truth.CoupledTruthRuntime.consumeReferenceSignalPathlossRuntime( ...
    state, "CSI-RS", "UE", 1, 15, 20);
assert(logical(selected.Usable) && double(selected.ProducerSlot) == 12 && ...
    double(selected.SelectedRow.Pathloss_dB) == 86.5 && ...
    string(selected.MeasurementId) == "CSI-RS_UE_1_slot_12" && ...
    string(selected.SelectedRow.PathlossReferenceRS) == "CSI-RS-resource-0", ...
    "Pathloss selection must retain the latest complete physical RS identity.");
end

function localValidateYAMLPathlossReferenceAuthority()
localAssertScenarioPathlossReference("lls_causal_access_to_data_wiring.yaml");
localAssertScenarioPathlossReference("lls_causal_access_to_data_wiring_tdd.yaml");
end

function localAssertScenarioPathlossReference(scenarioFile)
source = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    "simulator", "configs", "scenarios", scenarioFile));
cfg = sixgr.lls6g.buildInternalConfig(source, tempname);
ref = sixgr.util.structGet(cfg, ...
    "phy.pusch.powerControl.pathlossReference", struct());
assert(logical(sixgr.util.structGet(ref, "Available", false)) && ...
    string(sixgr.util.structGet(ref, "SignalType", "")) == "SSB" && ...
    double(sixgr.util.structGet(ref, "ReferenceSignalId", NaN)) == 0 && ...
    double(sixgr.util.structGet(ref, "PathlossReferenceRSId", NaN)) == 1 && ...
    double(sixgr.util.structGet(ref, "MaximumAgeSlots", NaN)) == 20, ...
    "Scenario %s must retain the YAML-owned SSB-0 pathloss reference.", ...
    scenarioFile);
end

