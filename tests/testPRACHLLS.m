function testTimingOffsetRecovery()
cfg = sixgr.rach.PRACHConfig(struct("ScenarioName", "timing_offset", ...
    "CarrierFrequencyHz", 700e6, "DuplexMode", "FDD", "NSizeGrid", 52, ...
    "PRACHConfigurationIndex", 16, "PRACHSubcarrierSpacing", 1.25, ...
    "PRACHFormat", "0", "ChannelModel", "AWGN"), "PreambleIndex", 7);
occ = sixgr.rach.mapPRACHToOccasion(cfg, "OccasionIndex", 1);
tx = sixgr.rach.generatePRACHWaveform(cfg, "Occasion", occ, "PreambleIndex", 7);
delaySamples = 11.25;
n = (0:size(tx.Waveform, 1)-1).';
rx = interp1(n, tx.Waveform, n - delaySamples, "linear", 0);
det = sixgr.rach.PRACHDetector(rx, cfg, "Occasion", occ, ...
    "DetectionThresholdMode", "fixed", "DetectionThreshold", 0.02);
timing = sixgr.rach.estimateTimingOffset(det.TimingOffsetSamples, tx.SampleRate_Hz, delaySamples);
assert(logical(det.Detected), "Timing-offset recovery case must detect the preamble.");
assert(det.DetectedPreambleIndex == 7 && det.DetectedPreambleIndexRaw == 7, ...
    "Tied root-sequence peaks must not replace the receiver-decoded cyclic-shift identity.");
assert(isfinite(det.TimingOffsetSamples), "A detected preamble must retain its measured timing.");
assert(isnan(det.CorrelationTrace.Threshold) && det.CorrelationTrace.DecisionThreshold==det.Threshold, ...
    "Do not overlay the NR decision threshold onto a different diagnostic correlation statistic.");
assert(abs(double(timing.Error_us)) < 0.1, ...
    "Timing-offset recovery error must stay below 0.1 us for the deterministic fractional-delay case.");
assert(isfield(det, "CorrelationTrace") && isstruct(det.CorrelationTrace), ...
    "PRACH detector must expose lag-domain correlation trace evidence.");
assert(all(ismember(["LagSamples","CorrelationAbs","PeakLagSamples","Threshold","NoiseFloor"], ...
    string(fieldnames(det.CorrelationTrace)))), ...
    "PRACH correlation trace must include lag, magnitude, peak, threshold, and noise-floor evidence.");
assert(numel(det.CorrelationTrace.LagSamples) == numel(det.CorrelationTrace.CorrelationAbs) && ...
    any(isfinite(double(det.CorrelationTrace.CorrelationAbs))), ...
    "PRACH correlation trace must contain finite per-lag correlation samples.");
assert(abs(double(det.CorrelationTrace.PeakLagSamples) - delaySamples) < 1.0, ...
    "PRACH correlation trace peak lag must track the known injected preamble delay.");
end

function testCorrelationTraceMissCase()
