function testRestrictedSetNCSValidation()
unrestricted = sixgr.rach.PRACHConfig(localScenario("ScenarioName", "ncs_unrestricted", ...
    "ZeroCorrelationZone", 8), "RestrictedSet", "UnrestrictedSet");
assert(isfinite(double(unrestricted.ZCZNCS)), ...
    "Unrestricted PRACH N_CS must resolve from the concrete 3GPP ZCZ table.");

restrictedA = sixgr.rach.PRACHConfig(localScenario("ScenarioName", "ncs_restricted_a", ...
    "ZeroCorrelationZone", 8), "RestrictedSet", "RestrictedSetTypeA");
assert(isfinite(double(restrictedA.ZCZNCS)), ...
    "Long-sequence restricted-set type A PRACH N_CS must resolve from the concrete 3GPP ZCZ table.");

restrictedB = sixgr.rach.PRACHConfig(localScenario("ScenarioName", "ncs_restricted_b", ...
    "ZeroCorrelationZone", 8), "RestrictedSet", "RestrictedSetTypeB");
assert(isfinite(double(restrictedB.ZCZNCS)), ...
    "Long-sequence restricted-set type B PRACH N_CS must resolve from the concrete 3GPP ZCZ table.");

shortFailedClosed = false;
try
    sixgr.rach.PRACHConfig(localShortPRACHScenario("short_restricted_set", ...
        "ZeroCorrelationZone", 8), "RestrictedSet", "RestrictedSetTypeA");
catch ME
    shortFailedClosed = any(strcmp(string(ME.identifier), ...
        ["sixgr:rach:PRACHConfig:RestrictedSetInvalidForShortFormat", ...
         "sixgr:phy:prach:RestrictedSetInvalidForShortFormat"]));
end
assert(shortFailedClosed, ...
    "Strict PRACH must fail closed for unsupported short-format restricted-set combinations.");
end

