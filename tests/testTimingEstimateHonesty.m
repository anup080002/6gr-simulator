function ok = testTimingEstimateHonesty()
%TESTTIMINGESTIMATEHONESTY Preserve raw timing truth separately from application policy.

setup6GRSimToolkit("Verbose", false);

testResolveTimingApplicationModes();
testPUSCHReceiverPreservesNegativeTrackingEstimate();
testDataReceiversDoNotCPClipAbsoluteAcquisitionOffset();
testKnownGeometryDelayIsSubtractedFromAppliedCorrection();
testKnownDelayDoesNotInvertEarlierPathTimingEstimate();

ok = true;
end

function testKnownDelayDoesNotInvertEarlierPathTimingEstimate()
if exist("nrPDSCH", "file") ~= 2 || exist("nrPUSCH", "file") ~= 2
    return;
end

cfg = sixgr.config.defaultConfig();
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.snr_dB = 25;
cfg.run.noiseOperatingMode = "receiver_noise_figure_thermal_noise";
cfg.phy.rx.useIdealTimingSync = false;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.lls6g.receiverSync.ChannelPathDelay_samples = 200;

rawOffset = 40;
tracking = struct( ...
    "TRSProcessed", true, ...
    "TrackingEstimateSource", "unit_test_early_path_acquisition", ...
    "TimingEstimateAvailable", true, ...
    "TimingEstimate_samples", rawOffset, ...
    "CFOEstimateAvailable", false, ...
    "EstimatedCFO_Hz", NaN);

[txDL, ~] = sixgr.phy.dl.PDSCH_Tx(cfg);
[rxDL, ~] = sixgr.phy.dl.PDSCH_Rx(txDL.Waveform, cfg, ...
    "Carrier", txDL.Carrier, ...
    "PDSCH", txDL.PDSCH, ...
    "PDSCHIndices", txDL.PDSCHIndices, ...
    "TransportBlockSize", txDL.TransportBlockSize, ...
    "TargetCodeRate", txDL.TargetCodeRate, ...
    "RV", txDL.RV, ...
    "NoiseVar", 1e-2, ...
    "ReceiverTrackingState", tracking, ...
    "SkipTimingEstimate", false);
assert(double(rxDL.RawTimingEstimate_samples) == rawOffset, ...
    "PDSCH receiver must preserve an early-path raw timing estimate.");
assert(abs(double(rxDL.KnownTimingDelay_samples) - 200) < 1e-9, ...
    "PDSCH receiver must still report the configured known channel path delay.");
assert(abs(double(rxDL.AppliedTimingCorrection_samples)) < 1e-9, ...
    "PDSCH receiver must not invert an early-path timing estimate into a negative correction.");

[txUL, ~] = sixgr.phy.ul.PUSCH_Tx(cfg);
[rxUL, ~] = sixgr.phy.ul.PUSCH_Rx(txUL.Waveform, cfg, ...
    "Carrier", txUL.Carrier, ...
    "PUSCH", txUL.PUSCH, ...
    "PUSCHIndices", txUL.PUSCHIndices, ...
    "TransportBlockSize", txUL.TransportBlockSize, ...
    "TargetCodeRate", txUL.TargetCodeRate, ...
    "RV", txUL.RV, ...
    "NoiseVar", 1e-2, ...
    "ReceiverTrackingState", tracking, ...
    "SkipTimingEstimate", false);
assert(double(rxUL.RawTimingEstimate_samples) == rawOffset, ...
    "PUSCH receiver must preserve an early-path raw timing estimate.");
assert(abs(double(rxUL.KnownTimingDelay_samples) - 200) < 1e-9, ...
    "PUSCH receiver must still report the configured known channel path delay.");
assert(abs(double(rxUL.AppliedTimingCorrection_samples)) < 1e-9, ...
    "PUSCH receiver must not invert an early-path timing estimate into a negative correction.");
end

function testKnownGeometryDelayIsSubtractedFromAppliedCorrection()
if exist("nrPDSCH", "file") ~= 2 || exist("nrPUSCH", "file") ~= 2
    return;
end

cfg = sixgr.config.defaultConfig();
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.snr_dB = 25;
cfg.run.noiseOperatingMode = "receiver_noise_figure_thermal_noise";
cfg.phy.rx.useIdealTimingSync = false;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;

rawOffset = 365;
knownGeometryDelay = 121;
knownChannelPathDelay = 200;
knownTotalDelay = knownGeometryDelay + knownChannelPathDelay;
tracking = struct( ...
    "TRSProcessed", true, ...
    "TrackingEstimateSource", "unit_test_absolute_acquisition_offset", ...
    "TimingEstimateAvailable", true, ...
    "TimingEstimate_samples", rawOffset, ...
    "CFOEstimateAvailable", false, ...
    "EstimatedCFO_Hz", NaN);

[txDL, ~] = sixgr.phy.dl.PDSCH_Tx(cfg);
ofdmDL = nrOFDMInfo(txDL.Carrier);
cfgDL = cfg;
cfgDL.channel.propagationDelay_s = double(knownGeometryDelay) / double(ofdmDL.SampleRate);
cfgDL.lls6g.receiverSync.ChannelPathDelay_samples = double(knownChannelPathDelay);
[rxDL, ~] = sixgr.phy.dl.PDSCH_Rx(txDL.Waveform, cfgDL, ...
    "Carrier", txDL.Carrier, ...
    "PDSCH", txDL.PDSCH, ...
    "PDSCHIndices", txDL.PDSCHIndices, ...
    "TransportBlockSize", txDL.TransportBlockSize, ...
    "TargetCodeRate", txDL.TargetCodeRate, ...
    "RV", txDL.RV, ...
    "NoiseVar", 1e-2, ...
    "ReceiverTrackingState", tracking, ...
    "SkipTimingEstimate", false);
assert(double(rxDL.RawTimingEstimate_samples) == rawOffset, ...
    "PDSCH receiver must preserve the raw absolute timing estimate.");
assert(abs(double(rxDL.KnownTimingDelay_samples) - knownTotalDelay) < 1e-9, ...
    "PDSCH receiver must combine configured geometry propagation delay and CDL path delay.");
assert(abs(double(rxDL.AppliedTimingCorrection_samples) - (rawOffset - knownTotalDelay)) < 1e-9, ...
    "PDSCH receiver must apply only the residual timing after known geometry/channel delay removal.");

[txUL, ~] = sixgr.phy.ul.PUSCH_Tx(cfg);
ofdmUL = nrOFDMInfo(txUL.Carrier);
cfgUL = cfg;
cfgUL.channel.propagationDelay_s = double(knownGeometryDelay) / double(ofdmUL.SampleRate);
cfgUL.lls6g.receiverSync.ChannelPathDelay_samples = double(knownChannelPathDelay);
[rxUL, ~] = sixgr.phy.ul.PUSCH_Rx(txUL.Waveform, cfgUL, ...
    "Carrier", txUL.Carrier, ...
    "PUSCH", txUL.PUSCH, ...
    "PUSCHIndices", txUL.PUSCHIndices, ...
    "TransportBlockSize", txUL.TransportBlockSize, ...
    "TargetCodeRate", txUL.TargetCodeRate, ...
    "RV", txUL.RV, ...
    "NoiseVar", 1e-2, ...
    "ReceiverTrackingState", tracking, ...
    "SkipTimingEstimate", false);
assert(double(rxUL.RawTimingEstimate_samples) == rawOffset, ...
    "PUSCH receiver must preserve the raw absolute timing estimate.");
assert(abs(double(rxUL.KnownTimingDelay_samples) - knownTotalDelay) < 1e-9, ...
    "PUSCH receiver must combine configured geometry propagation delay and CDL path delay.");
assert(abs(double(rxUL.AppliedTimingCorrection_samples) - (rawOffset - knownTotalDelay)) < 1e-9, ...
    "PUSCH receiver must apply only the residual timing after known geometry/channel delay removal.");
end

function testResolveTimingApplicationModes()
signed = sixgr.phy.sync.resolveTimingApplication(-7, ...
    "EstimateUsed", true, ...
    "ApplicationMode", "signed_waveform_shift", ...
    "Source", "unit_test_signed");
assert(double(signed.RawEstimate_samples) == -7, ...
    "Signed timing application must preserve the raw negative estimate.");
assert(double(signed.AppliedCorrection_samples) == -7, ...
    "Signed waveform timing correction must apply the negative estimate directly.");
assert(~logical(signed.WasClipped), ...
    "Signed waveform timing correction must not report clipping for negative offsets.");
assert(strcmpi(char(string(signed.Status)), "available_applied_signed_correction"), ...
    "Signed waveform timing correction must expose the explicit signed-application status.");

cropped = sixgr.phy.sync.resolveTimingApplication(-7, ...
    "EstimateUsed", true, ...
    "ApplicationMode", "positive_crop_only", ...
    "Source", "unit_test_crop");
assert(double(cropped.RawEstimate_samples) == -7, ...
    "Positive-crop-only timing application must still preserve the raw negative estimate.");
assert(double(cropped.AppliedCorrection_samples) == 0, ...
    "Positive-crop-only timing application must not silently apply a negative crop.");
assert(logical(cropped.WasClipped), ...
    "Positive-crop-only timing application must record that the raw negative estimate was not applied.");
assert(strcmpi(char(string(cropped.Status)), "available_raw_negative_not_applied"), ...
    "Positive-crop-only timing application must expose the non-applied negative-estimate status.");
end

