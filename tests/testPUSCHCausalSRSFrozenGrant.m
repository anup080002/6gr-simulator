function ok = testPUSCHCausalSRSFrozenGrant()
%TESTPUSCHCAUSALSRSFROZENGRANT Prove SRS -> grant -> waveform TPMI identity.

cfg = sixgr.config.defaultConfig();
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.phy.carrier.NSizeGrid = 18;
cfg.phy.carrier.SubcarrierSpacing = 30;
cfg.phy.NCellID = 41;
cfg.phy.ueArray = [2 2 1];
cfg.antenna.ue.numElements = 4;
cfg.scenario.ue.nTxAnt = 4;
cfg.rf.ue.hybridBeamformingEnabled = true;
cfg.rf.ue.numRFChains = 2;
cfg.phy.mimo.strict = true;
cfg.phy.pusch.numLayers = 2;
cfg.phy.pusch.nLayers = 2;
cfg.phy.pusch.NumAntennaPorts = 2;
cfg.phy.pusch.numPorts = 2;
cfg.phy.pusch.nPorts = 2;
cfg.phy.pusch.TransmissionScheme = "codebook";
cfg.phy.pusch.transmissionScheme = "codebook";
cfg.phy.pusch.CodebookType = "codebook1_ng1n4n1";
cfg.phy.pusch.TPMI = 0;
cfg.phy.pusch.PMI = 0;
cfg.phy.pusch.transformPrecoding = false;
cfg.phy.pusch.modulation = "QPSK";
cfg.phy.pusch.codeRate = 0.30;
cfg.phy.pusch.prbSet = 0:5;
cfg.phy.pusch.symbolAllocation = [0 14];
cfg.phy.pusch.RNTI = 701;
cfg.phy.pusch.NID = 41;
cfg.phy.pusch.dmrs.portSet = [0 1];

carrier = sixgr.phy.grid.makeCarrier(cfg);
[puschInd, puschInfo, pusch] = sixgr.phy.grid.allocREsPUSCH(carrier, cfg, ...
    "FixedReferenceMode", true);
acct = sixgr.phy.resource.computeResourceAccounting("PUSCH", carrier, pusch, ...
    "ChannelIndices", puschInd, "AllocationInfo", puschInfo, ...
    "IndexBase", "1based", "TargetCodeRate", cfg.phy.pusch.codeRate, ...
    "XOverhead", 0);
tbs = double(nrTBS(pusch.Modulation, pusch.NumLayers, ...
    numel(pusch.PRBSet), acct.NREPerPRBForTBS, cfg.phy.pusch.codeRate, 0));

grant = localGrant(cfg, pusch, acct, tbs);
phyGrant = sixgr.phy.grant.freezePHYGrant(cfg, "UL", grant, ...
    "Frame", 0, "Slot", 7);
prec = phyGrant.PrecodingState;
assert(logical(prec.NativeCodebookApplied) && ...
    logical(prec.AuthoritativeSRSDecisionUsed), ...
    "Frozen UL grant must bind native codebook application to causal SRS.");
assert(double(prec.TPMI) == 0 && double(prec.PMI) == 0, ...
    "Frozen UL grant must retain the causal TPMI exactly.");
assert(string(prec.SelectedMatrixSHA256) == ...
    string(sixgr.phy.mimo.MatrixContract.digest(prec.MatrixLogicalPorts)), ...
    "Selected matrix hash must identify the logical TPMI codebook matrix.");
assert(string(prec.AppliedMatrixSHA256) == ...
    string(sixgr.phy.mimo.MatrixContract.digest(prec.MatrixPorts)), ...
    "Applied matrix hash must identify the physical hybrid matrix.");

[tx, info] = sixgr.phy.ul.PUSCH_Tx(cfg, "PHYGrant", phyGrant, ...
    "CompactOutput", false);
assert(logical(info.Precoding.AuthoritativeSRSDecisionUsed) && ...
    double(info.Precoding.PMI) == 0, ...
    "PUSCH transmitter must consume the SRS decision frozen in the grant.");
assert(string(info.Precoding.SelectedMatrixSHA256) == ...
    string(prec.SelectedMatrixSHA256) && ...
    string(info.Precoding.AppliedMatrixSHA256) == ...
    string(prec.AppliedMatrixSHA256), ...
    "PUSCH transmitter logical and physical precoder hashes must match the frozen grant.");
assert(size(tx.Waveform, 2) == 4, ...
    "Hybrid PUSCH must materialize all four configured UE antenna elements.");

missing = grant;
missing.SRSCausalUsable = false;
localAssertThrows(@()sixgr.phy.grant.freezePHYGrant(cfg, "UL", missing, ...
    "Frame", 0, "Slot", 7), "sixgr:mimo:MissingSRSState");

wrongRank = grant;
wrongRank.RI = 1;
wrongRank.RIUsed = 1;
localAssertThrows(@()sixgr.phy.grant.freezePHYGrant(cfg, "UL", wrongRank, ...
    "Frame", 0, "Slot", 7), "sixgr:mimo:RankIdentityMismatch");
ok = true;
end

function grant = localGrant(cfg, pusch, acct, tbs)
grant = struct( ...
    "Direction", "UL", "Frame", 0, "Slot", 7, ...
    "RNTI", double(pusch.RNTI), "UEIndex", 1, "ServingCell", 1, ...
    "PRBSet", double(pusch.PRBSet), ...
    "SymbolAllocation", double(pusch.SymbolAllocation), ...
    "MappingType", char(pusch.MappingType), ...
    "Modulation", char(pusch.Modulation), ...
    "NumLayers", 2, "Layers", 2, "RI", 2, "RIUsed", 2, ...
    "NumLogicalPorts", 2, "NumElements", 4, "NumRFChains", 2, ...
    "TargetCodeRate", double(cfg.phy.pusch.codeRate), ...
    "XOverhead", 0, "NREPerPRB", double(acct.NREPerPRBForTBS), ...
    "TBSBits", double(tbs), "TBSBytes", floor(double(tbs) / 8), ...
    "MCSIndex", 1, "MCS", 1, "MCSTable", "qam256", ...
    "TransmissionScheme", "codebook", "CodebookType", "codebook1_ng1n4n1", ...
    "TransformPrecoding", false, "TPMI", 0, "PMI", 0, ...
    "SRSValid", true, "SRSCausalUsable", true, ...
    "SRSCausalMeasurementId", "srs|ue=1|slot=5|epoch=0", ...
    "LastSuccessfulSRSSlot", 5, "SRSAgeSlots", 2, ...
    "GrantContextId", "UL|causal-srs|ue=1|slot=7", ...
    "HARQ", struct("HarqID", 0, "NDI", true, "RV", 0, ...
    "IsRetransmission", false));
end

function localAssertThrows(fh, expectedId)
try
    fh();
catch ME
    assert(strcmp(ME.identifier, expectedId), ...
        "Expected %s, got %s: %s", expectedId, ME.identifier, ME.message);
    return;
end
error("ExpectedException:notThrown", "Expected %s to be thrown.", expectedId);
end
