function test6GCSIReportingCoverage()
%TEST6GCSIREPORTINGCOVERAGE Verify PMI/RI/CRI/CSI surfaces are explicit in YAML, chains, and runtime config.

repoRoot = fileparts(fileparts(mfilename("fullpath")));
packPath = fullfile(repoRoot, "simulator", "configs", "reference_signals", "csi_tracking_baseline.yaml");
pack = sixgr.lls6g.config.readConfigFile(packPath);

assert(isfield(pack, "reference_signals"), ...
    "sixgr:test:6GCSIReporting:MissingReferenceSignals", ...
    "Reference-signal pack must expose a reference_signals section.");
assert(isfield(pack, "csi_acquisition_and_reporting"), ...
    "sixgr:test:6GCSIReporting:MissingCSISection", ...
    "Reference-signal pack must expose csi_acquisition_and_reporting overrides.");

rs = pack.reference_signals;
assert(isfield(rs, "csi_reporting_enabled"), ...
    "sixgr:test:6GCSIReporting:MissingCSIReporting", ...
    "reference_signals must expose csi_reporting_enabled.");
assert(isfield(rs, "cri_reporting_enabled"), ...
    "sixgr:test:6GCSIReporting:MissingCRIReporting", ...
    "reference_signals must expose cri_reporting_enabled.");
assert(isfield(rs, "pmi_codebook_mode"), ...
    "sixgr:test:6GCSIReporting:MissingPMICodebookMode", ...
    "reference_signals must expose pmi_codebook_mode.");
assert(isfield(rs, "channel_state_information_mode"), ...
    "sixgr:test:6GCSIReporting:MissingCSIMode", ...
    "reference_signals must expose channel_state_information_mode.");

csi = pack.csi_acquisition_and_reporting;
assert(isfield(csi, "pmi_codebook_mode"), ...
    "sixgr:test:6GCSIReporting:MissingCanonicalPMIMode", ...
    "csi_acquisition_and_reporting must expose pmi_codebook_mode.");
assert(isfield(csi, "cri_policy"), ...
    "sixgr:test:6GCSIReporting:MissingCRIPolicy", ...
    "csi_acquisition_and_reporting must expose cri_policy.");
assert(isfield(csi, "channel_state_information_mode"), ...
    "sixgr:test:6GCSIReporting:MissingCanonicalCSIMode", ...
    "csi_acquisition_and_reporting must expose channel_state_information_mode.");

scenarioPath = fullfile(repoRoot, "simulator", "configs", "scenarios", "dl_4ghz_baseline.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
s = scfg.toStruct();
pc = s.processing_chains.csi_acquisition_reporting;
blockIds = string({pc.ordered_blocks.block_id});
assert(any(blockIds == "codebook_cri_candidate_generation"), ...
    "sixgr:test:6GCSIReporting:MissingCodebookBlock", ...
    "CSI processing chain must expose codebook_cri_candidate_generation.");
assert(any(blockIds == "cqi_pmi_ri_cri_computation"), ...
    "sixgr:test:6GCSIReporting:MissingCSIComputeBlock", ...
    "CSI processing chain must expose cqi_pmi_ri_cri_computation.");

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

cfgPath = fullfile(tmp, "csi_reporting_contract.yaml");
fid = fopen(cfgPath, "w");
fprintf(fid, "%s", ['{' ...
    '"inherits":["' strrep(scenarioPath, '\', '\\') '"],' ...
    '"reference_signals":{"csi_reporting_enabled":true,"csi_feedback_mode":"PMI+CQI+RI+CRI","cqi_reporting_enabled":true,"pmi_reporting_enabled":true,"ri_reporting_enabled":true,"cri_reporting_enabled":true,"pmi_codebook_mode":"etype2_candidate","channel_state_information_mode":"PMI+CQI+RI+CRI","srs_ports":4},' ...
    '"csi_acquisition_and_reporting":{"pmi_policy":"baseline","ri_policy":"baseline","cri_policy":"baseline","channel_state_information_mode":"PMI+CQI+RI+CRI","pmi_codebook_mode":"etype2_candidate","report_configuration":{"report_config_id":"etype2-subband-test","epoch":1,"codebook_mode":2,"report_quantity":"cri-RI-PMI-CQI","frequency_granularity":"subband","uci_channel":"PUCCH","n1":1,"n2":1,"o1":1,"o2":1,"panels":1,"num_subbands":2,"number_of_beams":2,"phase_alphabet_size":4}},' ...
    '"mimo":{"codebook_type":"etype2"}}']);
fclose(fid);

resolved = sixgr.lls6g.config.loadScenarioConfig(cfgPath);
cfg = sixgr.lls6g.buildInternalConfig(resolved, fullfile(tmp, "run"));

assert(logical(sixgr.util.structGet(cfg, "phy.csi.reportCSI")), ...
    "sixgr:test:6GCSIReporting:RuntimeMissingCSI", ...
    "Runtime config must enable generic CSI reporting.");
assert(logical(sixgr.util.structGet(cfg, "phy.csi.reportPMI")), ...
    "sixgr:test:6GCSIReporting:RuntimeMissingPMI", ...
    "Runtime config must enable PMI reporting.");
assert(logical(sixgr.util.structGet(cfg, "phy.csi.reportRI")), ...
    "sixgr:test:6GCSIReporting:RuntimeMissingRI", ...
    "Runtime config must enable RI reporting.");
assert(logical(sixgr.util.structGet(cfg, "phy.csi.reportCRI")), ...
    "sixgr:test:6GCSIReporting:RuntimeMissingCRI", ...
    "Runtime config must enable CRI reporting.");
assert(strcmpi(string(sixgr.util.structGet(cfg, "phy.csi.pmiCodebookMode")), "etype2_candidate"), ...
    "sixgr:test:6GCSIReporting:RuntimeBadPMIMode", ...
    "Runtime config must carry the configured PMI codebook mode.");
assert(strcmpi(string(sixgr.util.structGet(cfg, "phy.csi.codebookType")), "etype2"), ...
    "sixgr:test:6GCSIReporting:RuntimeBadCodebookType", ...
    "Runtime config must carry the configured codebook family.");
assert(strcmpi(string(sixgr.util.structGet(cfg, "phy.csi.channelStateInformationMode")), "PMI+CQI+RI+CRI"), ...
    "sixgr:test:6GCSIReporting:RuntimeBadCSIMode", ...
    "Runtime config must carry the configured CSI payload mode.");
assert(logical(sixgr.util.structGet(cfg, "phy.csi.reportPMIEnhancedType2")), ...
    "sixgr:test:6GCSIReporting:RuntimeBadEType2", ...
    "Runtime config must mark eType2 PMI mode.");
assert(double(sixgr.util.structGet(cfg, "phy.srs.nPorts")) == 4, ...
    "sixgr:test:6GCSIReporting:RuntimeBadSRSPorts", ...
    "Runtime config must source SRS ports from reference_signals.srs_ports.");
end
