function ok = testPDSCHMCSResolver()
%TESTPDSCHMCSRESOLVER Compare every table entry with R2026a normative data.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
catalog = nrPDSCHMCSTables;
spec = { ...
    "qam64", catalog.QAM64Table; ...
    "qam256", catalog.QAM256Table; ...
    "qam64lowse", catalog.QAM64LowSETable; ...
    "qam1024", catalog.QAM1024Table};
context = struct( ...
    "NumCodewords", 1, ...
    "NumLayers", 1, ...
    "UECapability1024QAM", true, ...
    "UECapability1024QAMVariant", ...
        "pdsch-1024qam-fr1-r17", ...
    "MaxNumberMIMOLayersPDSCH", 8, ...
    "RRCEnabled1024QAM", true, ...
    "DCIEnabled1024QAM", true, ...
    "DCIFormat", "1_1", ...
    "DeploymentAllows1024QAM", true, ...
    "FrequencyRange", "FR1", ...
    "OperatingBand", "n78", ...
    "DeploymentClass", "controlled_test", ...
    "FrequencyRangeAllows1024QAM", true, ...
    "BandAllows1024QAM", true, ...
    "RNTIType", "C-RNTI", ...
    "SelectionSource", "decoded_dci+rrc_context");

validCount = 0;
reservedCount = 0;
for tableIndex = 1:size(spec, 1)
    name = spec{tableIndex, 1};
    reference = spec{tableIndex, 2};
    for mcsIndex = 0:31
        ref = reference(mcsIndex + 1, :);
        if ~isfinite(double(ref.TargetCodeRate))
            localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
                name, mcsIndex, context), "sixgr:pdsch:ReservedMCSEntry");
            reservedCount = reservedCount + 1;
        else
            actual = sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
                name, mcsIndex, context);
            assert(actual.Qm == double(ref.Qm));
            assert(abs(actual.TargetCodeRate - double(ref.TargetCodeRate)) < 1e-14);
            assert(abs(actual.SpectralEfficiency - double(ref.SpectralEfficiency)) < 1e-14);
            assert(strcmpi(actual.Modulation, string(ref.Modulation{1})));
            validCount = validCount + 1;
        end
    end
end

bands = sixgr.pdsch.PDSCH1024QAMApplicability.bandCatalog();
deployments = sixgr.pdsch.PDSCH1024QAMApplicability.deploymentCatalog();
dciFormats = sixgr.pdsch.PDSCH1024QAMApplicability.dciFormatCatalog();
capabilities = ...
    sixgr.pdsch.PDSCH1024QAMApplicability.capabilityCatalog();
assert(height(bands) == 74);
assert(height(deployments) == 5);
assert(height(dciFormats) == 3);
assert(height(capabilities) == 2);
assert(numel(unique(capabilities.MutualExclusionGroup)) == 1);
localAssertCompleteBandCatalog(bands);
localAssertCatalogRow(bands, "n1", "FR1", "FDD", true);
localAssertCatalogRow(bands, "n78", "FR1", "TDD", true);
localAssertCatalogRow(bands, "n80", "FR1", "SUL", false);
localAssertCatalogRow(bands, "n257", "FR2-1", "TDD", true);
localAssertCatalogRow(bands, "n263", "FR2-2", "TDD", true);
assert(isequal(dciFormats.DCIFormat,["1_1";"1_2";"1_3"]));
assert(isequal(dciFormats.RRCSelectionField, ...
    ["mcs-Table-r17";"mcs-TableDCI-1-2-r17";"mcs-Table-r17"]));
assert(all(dciFormats.AllowedRNTIType == "C-RNTI"));
assert(all(dciFormats.SourceClause == ...
    "3GPP_TS_38_214_V18_8_0_CLAUSE_5_1_3_1"));
assert(all(dciFormats.SourceArchive == "38214-i80.zip"));
assert(all(dciFormats.SourceArchiveSHA256 == ...
    "46b5d9be58e0fc1dcab368a27f5ffdee8c94c48327bd65d3abbfc00f602136fa"));
assert(all(capabilities.SourceArchive == "38306-i80.zip"));
assert(all(capabilities.SourceArchiveSHA256 == ...
    "5d237e4832df12cbd0ed1c736a19d92ea054bf325553704f85b566fbfb18ef0e"));

validFDD = context;
validFDD.OperatingBand = "n1";
validFDD.DeploymentClass = "fdd";
validFDD.DCIFormat = "1_2";
fddProfile = sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, validFDD);
assert(string(fddProfile.Modulation) == "1024QAM");
validSDL = context;
validSDL.OperatingBand = "n29";
validSDL.DeploymentClass = "sdl";
sdlProfile = sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, validSDL);
assert(string(sdlProfile.Modulation) == "1024QAM");
validReduced = context;
validReduced.NumLayers = 2;
validReduced.UECapability1024QAMVariant = ...
    "pdsch-1024qam-2mimo-fr1-r17";
validReduced.MaxNumberMIMOLayersPDSCH = 4;
reducedProfile = sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, validReduced);
assert(string(reducedProfile.Modulation) == "1024QAM");
validDCI13 = context;
validDCI13.DCIFormat = "1_3";
dci13Profile = sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, validDCI13);
assert(string(dci13Profile.Modulation) == "1024QAM");

assignmentVectors = readtable(fullfile( ...
    PDSCHPhaseTestSupport.vectorRoot(), ...
    "pdsch_scheduling_assignment_test_vectors.csv"), ...
    "TextType","string","VariableNamingRule","preserve");
factoryRow = assignmentVectors(1,:);
factoryRow.DCIFormat = "1_3";
factoryRow.MCSTable = "qam1024";
factoryRow.MCSIndex = 23;
[decoded,ue,frame,harq] = ...
    PDSCHPhaseTestSupport.assignmentInputs(factoryRow);
dci13Assignment = sixgr.pdsch.PDSCHAssignmentFactory.fromDecodedDCI( ...
    decoded,sixgr.pdsch.PDSCHUEContext(ue),frame,harq);
assert(string(dci13Assignment.get("DCIFormat")) == "1_3");
assert(string(dci13Assignment.get("ModulationPerCodeword")) == "1024QAM");

unsupported = context;
unsupported.UECapability1024QAM = false;
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, unsupported), "sixgr:pdsch:UnsupportedMCSContext");

missingRange = rmfield(context, "FrequencyRange");
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, missingRange), ...
    "sixgr:pdsch:Missing1024QAMFrequencyRangeContext");
badRange = context; badRange.FrequencyRange = "FR3";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, badRange), ...
    "sixgr:pdsch:Unsupported1024QAMFrequencyRange");
missingBand = rmfield(context, "OperatingBand");
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, missingBand), ...
    "sixgr:pdsch:Missing1024QAMBandContext");
badBand = context; badBand.OperatingBand = "band-78";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, badBand), ...
    "sixgr:pdsch:Invalid1024QAMOperatingBand");
missingClass = rmfield(context, "DeploymentClass");
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, missingClass), ...
    "sixgr:pdsch:Missing1024QAMDeploymentClass");
missingDCIFormat = rmfield(context, "DCIFormat");
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, missingDCIFormat), ...
    "sixgr:pdsch:Missing1024QAMDCIFormat");
deniedRange = context; deniedRange.FrequencyRangeAllows1024QAM = false;
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, deniedRange), ...
    "sixgr:pdsch:QAM1024FrequencyRangeNotAllowed");
deniedBand = context; deniedBand.BandAllows1024QAM = false;
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, deniedBand), ...
    "sixgr:pdsch:QAM1024BandNotAllowed");
deniedDeployment = context;
deniedDeployment.DeploymentAllows1024QAM = false;
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, deniedDeployment), ...
    "sixgr:pdsch:QAM1024DeploymentClassNotAllowed");

fr2 = context;
fr2.FrequencyRange = "FR2-1";
fr2.OperatingBand = "n257";
fr2.DeploymentClass = "tdd";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, fr2), ...
    "sixgr:pdsch:QAM1024FrequencyRangeNotAllowed");
bandRangeMismatch = context;
bandRangeMismatch.OperatingBand = "n257";
bandRangeMismatch.DeploymentClass = "tdd";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, bandRangeMismatch), ...
    "sixgr:pdsch:QAM1024BandRangeMismatch");
unknownBand = context;
unknownBand.OperatingBand = "n999";
unknownBand.DeploymentClass = "tdd";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, unknownBand), ...
    "sixgr:pdsch:QAM1024BandNotInPinnedCatalog");
arbitraryDeployment = context;
arbitraryDeployment.DeploymentClass = "arbitrary_lab";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, arbitraryDeployment), ...
    "sixgr:pdsch:QAM1024DeploymentClassNotInPinnedCatalog");
deploymentMismatch = context;
deploymentMismatch.DeploymentClass = "fdd";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, deploymentMismatch), ...
    "sixgr:pdsch:QAM1024DeploymentBandMismatch");
sulBand = context;
sulBand.OperatingBand = "n80";
sulBand.DeploymentClass = "sul";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, sulBand), ...
    "sixgr:pdsch:QAM1024DownlinkBandRequired");
badDCIFormat = context;
badDCIFormat.DCIFormat = "1_0";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, badDCIFormat), ...
    "sixgr:pdsch:QAM1024DCIFormatNotAllowed");
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 0, badDCIFormat), ...
    "sixgr:pdsch:QAM1024DCIFormatNotAllowed");
badRNTI = context;
badRNTI.RNTIType = "MCS-C-RNTI";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, badRNTI), ...
    "sixgr:pdsch:QAM1024RNTIProcedureNotAllowed");
badCSRNTI = context;
badCSRNTI.RNTIType = "CS-RNTI";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, badCSRNTI), ...
    "sixgr:pdsch:QAM1024RNTIProcedureNotAllowed");
missingVariant = rmfield(context, "UECapability1024QAMVariant");
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, missingVariant), ...
    "sixgr:pdsch:Missing1024QAMCapabilityVariant");
dualVariant = context;
dualVariant.UECapability1024QAMVariant = [ ...
    "pdsch-1024qam-fr1-r17", ...
    "pdsch-1024qam-2mimo-fr1-r17"];
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, dualVariant), ...
    "sixgr:pdsch:QAM1024CapabilityVariantsMutuallyExclusive");
unknownVariant = context;
unknownVariant.UECapability1024QAMVariant = "generic_1024qam";
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, unknownVariant), ...
    "sixgr:pdsch:QAM1024CapabilityVariantNotInPinnedCatalog");
missingMaxLayers = rmfield(context, "MaxNumberMIMOLayersPDSCH");
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, missingMaxLayers), ...
    "sixgr:pdsch:Missing1024QAMMaxNumberMIMOLayersPDSCH");
badMaxLayers = context;
badMaxLayers.MaxNumberMIMOLayersPDSCH = 9;
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, badMaxLayers), ...
    "sixgr:pdsch:Invalid1024QAMMaxNumberMIMOLayersPDSCH");
missingNumLayers = rmfield(context, "NumLayers");
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, missingNumLayers), ...
    "sixgr:pdsch:Missing1024QAMNumLayers");
badNumLayers = context;
badNumLayers.NumLayers = 1.5;
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, badNumLayers), ...
    "sixgr:pdsch:Invalid1024QAMNumLayers");
reducedOverRank = validReduced;
reducedOverRank.NumLayers = 3;
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, reducedOverRank), ...
    "sixgr:pdsch:QAM1024LayerCapabilityExceeded");
fullOverConfiguredMax = context;
fullOverConfiguredMax.NumLayers = 3;
fullOverConfiguredMax.MaxNumberMIMOLayersPDSCH = 2;
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "qam1024", 23, fullOverConfiguredMax), ...
    "sixgr:pdsch:QAM1024LayerCapabilityExceeded");
localAssertError(@() sixgr.pdsch.PDSCHMCSResolver.resolveOne( ...
    "missing", 0, context), "sixgr:pdsch:MissingMCSTable");

two = context; two.NumCodewords = 2;
profiles = sixgr.pdsch.PDSCHMCSResolver.resolve( ...
    ["qam64","qam256"], [4 20], two);
assert(numel(profiles) == 2 && profiles(1).Qm == 2 && profiles(2).Qm == 8);
fprintf('PDSCH MCS resolver: %d normative entries and %d reserved entries passed.\n', ...
    validCount, reservedCount);
fprintf('%s\n',char( ...
    "PDSCH 1024QAM applicability: 74 bands, 5 deployment " + ...
    "bindings, 3 DCI formats, 2 capability variants, 4 additional " + ...
    "valid resolver contexts, 1 connected-strict DCI 1_3 assignment, and " + ...
    "30 explicit negative contexts passed."));
ok = true;
end

function localAssertCompleteBandCatalog(catalog)
% Frozen from the official 3GPP i80 Table 5.2-1 archives, not inferred
% from catalog height or representative rows.
fdd = [ ...
    "n1","n2","n3","n5","n7","n8","n12","n13","n14", ...
    "n18","n20","n24","n25","n26","n28","n30","n31", ...
    "n65","n66","n70","n71","n72","n74","n85", ...
    "n91","n92","n93","n94","n100","n105","n106","n109"];
tdd = [ ...
    "n34","n38","n39","n40","n41","n46","n47","n48", ...
    "n50","n51","n53","n54","n77","n78","n79","n90", ...
    "n96","n101","n102","n104"];
sdl = ["n29","n67","n75","n76"];
sul = [ ...
    "n80","n81","n82","n83","n84","n86","n89", ...
    "n95","n97","n98","n99"];
fr21 = ["n257","n258","n259","n260","n261","n262"];
fr22 = "n263";
expectedBand = [fdd,tdd,sdl,sul,fr21,fr22].';
expectedRange = [ ...
    repmat("FR1",1,numel(fdd)+numel(tdd)+numel(sdl)+numel(sul)), ...
    repmat("FR2-1",1,numel(fr21)),"FR2-2"].';
expectedDuplex = [ ...
    repmat("FDD",1,numel(fdd)),repmat("TDD",1,numel(tdd)), ...
    repmat("SDL",1,numel(sdl)),repmat("SUL",1,numel(sul)), ...
    repmat("TDD",1,numel(fr21)+numel(fr22))].';
expectedDownlink = expectedDuplex ~= "SUL";
expectedNumber = str2double(extractAfter(expectedBand,1));
[~,order] = sort(expectedNumber);
expectedBand = expectedBand(order);
expectedRange = expectedRange(order);
expectedDuplex = expectedDuplex(order);
expectedDownlink = expectedDownlink(order);
assert(isequal(catalog.OperatingBand,expectedBand));
assert(isequal(catalog.FrequencyRange,expectedRange));
assert(isequal(catalog.DuplexMode,expectedDuplex));
assert(isequal(catalog.DownlinkCapable,expectedDownlink));
fr1 = catalog.FrequencyRange == "FR1";
assert(all(catalog.SourceArchive(fr1) == "38101-1-i80.zip"));
assert(all(catalog.SourceArchiveSHA256(fr1) == ...
    "d73d492aa8a87fad9cdd415e95fbaf7101852f077b78f4dbdda665084ec3ba0f"));
assert(all(catalog.SourceArchive(~fr1) == "38101-2-i80.zip"));
assert(all(catalog.SourceArchiveSHA256(~fr1) == ...
    "30117b861385c49d49c572ced81d6136e2349daea4da3a1142ab3362986337f2"));
end

function localAssertCatalogRow(catalog, band, range, duplex, downlink)
row = catalog(catalog.OperatingBand == band, :);
assert(height(row) == 1, "Expected one catalog row for %s.", band);
assert(row.FrequencyRange == range);
assert(row.DuplexMode == duplex);
assert(row.DownlinkCapable == downlink);
end

function localAssertError(fn, id)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(id), ...
        "Expected %s, got %s.", id, ME.identifier);
    return;
end
error("testPDSCHMCSResolver:MissingError", "Expected %s.", id);
end
