function ok = testLLSNumerologyTimingConsistency()
%TESTLLSNUMEROLOGYTIMINGCONSISTENCY Ensure resolved LLS numerology/timing follows SCS truthfully.

setup6GRSimToolkit("Verbose", false);

scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, tempname);

assert(double(scfg.get("global_radio_scope.numerology_mu")) == 0, ...
    "Resolved scenario aliases must derive numerology mu from the active 15 kHz SCS.");
assert(abs(double(scfg.get("frame_timing.slot_duration_ms")) - 1.0) < 1e-12, ...
    "Resolved scenario aliases must derive slot duration from the active numerology.");
assert(double(scfg.get("frame_timing.slots_per_frame")) == 10, ...
    "Resolved scenario aliases must derive slots-per-frame from the active numerology.");
assert(double(scfg.get("resource_grid.num_rbs")) == 106, ...
    "Resolved scenario aliases must align the full-band resource-grid RB count with frequency.n_size_grid.");

assert(double(sixgr.util.structGet(cfg, "phy.numerology.scs_kHz", NaN)) == 15, ...
    "Browser-owned LLS scenario must resolve the active carrier SCS to 15 kHz.");
assert(double(sixgr.util.structGet(cfg, "phy.numerology.mu", NaN)) == 0, ...
    "Resolved numerology mu must be derived from the active 15 kHz SCS.");
assert(abs(double(sixgr.util.structGet(cfg, "phy.numerology.slotDuration_ms", NaN)) - 1.0) < 1e-12, ...
    "Resolved slot duration must match mu=0 timing (1 ms).");
assert(double(sixgr.util.structGet(cfg, "phy.numerology.slotsPerFrame", NaN)) == 10, ...
    "Resolved slots-per-frame must match mu=0 timing.");
assert(double(sixgr.util.structGet(cfg, "phy.numerology.symbolsPerSlot", NaN)) == 14, ...
    "Resolved symbols-per-slot must preserve normal CP timing.");
assert(double(sixgr.util.structGet(cfg, "phy.numerology.activeGridNumRBs", NaN)) == 106, ...
    "Resolved active grid must preserve the browser-owned 20 MHz / 15 kHz carrier grid.");
assert(double(sixgr.util.structGet(cfg, "phy.numerology.configuredGridNumRBs", NaN)) == 106, ...
    "Configured grid RBs must remain aligned with the active browser-owned carrier grid.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.numerology.activeGridSource", ""))), "configured_n_size_grid"), ...
    "Active grid source must disclose that the runtime grid came from the resolved NSizeGrid field.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.numerology.numerologySource", ""))), "carrier_subcarrier_spacing_khz"), ...
    "Numerology source must disclose that mu was derived from the resolved SCS.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.numerology.timingInterpretationSource", ""))), "nr_mu_from_scs"), ...
    "Timing interpretation source must disclose that slot timing was derived from NR numerology.");

ok = true;
end
