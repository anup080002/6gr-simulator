function ok = testPDSCHPTRSPresenceVectors()
%TESTPDSCHPTRSPRESENCEVECTORS Execute all 56 frozen PT-RS presence rows.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
vectors = readPDSCHVectorTable("pdsch_ptrs_test_vectors.csv");
golden = readPDSCHVectorTable("expected_pdsch_ptrs_presence.csv");
assert(height(vectors) == 56 && height(golden) == 56, ...
    "The complete 56-row PT-RS presence matrix is mandatory.");
assert(isequal(vectors.CaseID, golden.CaseID), ...
    "PT-RS input and expected case IDs differ.");

policy = struct( ...
    "MinimumPRBs", 3, ...
    "MinimumDurationSymbols", 3, ...
    "MinimumMCSIndex", 0, ...
    "AllowedRNTITypes", "C-RNTI");
presentCount = 0;
absentCount = 0;
negativeCount = 0;
for i = 1:height(vectors)
    request = localRequest(vectors(i, :));
    before = request;
    expectedPresent = logical(str2double(golden.ExpectedPresent(i)));
    expectedStatus = golden.ExpectedStatus(i);
    expectedReason = golden.ExpectedReason(i);

    assert(expectedPresent == ...
        logical(str2double(vectors.ExpectedPTRSPresent(i))), ...
        "Input/expected presence mismatch for %s.", vectors.CaseID(i));
    assert(expectedStatus == vectors.ExpectedStatus(i), ...
        "Input/expected status mismatch for %s.", vectors.CaseID(i));
    assert(expectedReason == vectors.ExpectedReason(i), ...
        "Input/expected reason mismatch for %s.", vectors.CaseID(i));

    if expectedStatus == "PASS"
        actual = sixgr.pdsch.PDSCHPTRSResolver.resolve(request, policy);
        assert(actual.Present == expectedPresent, ...
            "PT-RS presence mismatch for %s.", vectors.CaseID(i));
        assert(actual.Status == expectedStatus && ...
            actual.Reason == expectedReason, ...
            "PT-RS status/reason mismatch for %s.", vectors.CaseID(i));
        assert(actual.OriginalUnchanged && isequaln(request, before), ...
            "PT-RS resolver mutated %s.", vectors.CaseID(i));
        if actual.Present
            presentCount = presentCount + 1;
        else
            absentCount = absentCount + 1;
        end
    else
        expectedID = "sixgr:pdsch:" + expectedReason;
        localAssertError(@() sixgr.pdsch.PDSCHPTRSResolver. ...
            resolve(request, policy), expectedID);
        assert(isequaln(request, before), ...
            "Rejected PT-RS resolution mutated %s.", vectors.CaseID(i));
        negativeCount = negativeCount + 1;
    end
end
assert(presentCount == 48 && absentCount == 5 && negativeCount == 3, ...
    "Unexpected PT-RS present/absent/error execution counts.");
ok = true;
end

function request = localRequest(row)
request = struct( ...
    "MappingType", row.MappingType(1), ...
    "TimeDensity", str2double(row.TimeDensity(1)), ...
    "FrequencyDensity", str2double(row.FrequencyDensity(1)), ...
    "REOffset", row.REOffset(1), ...
    "PDSCHDuration", str2double(row.PDSCHDuration(1)), ...
    "NPRB", str2double(row.NPRB(1)), ...
    "MCSIndex", str2double(row.MCSIndex(1)), ...
    "MCSTable", row.MCSTable(1), ...
    "RNTIType", row.RNTIType(1), ...
    "PTRSPortSet", pdschVectorDecodeIntegers(row.PTRSPortSet(1)), ...
    "DMRSPortSet", pdschVectorDecodeIntegers(row.DMRSPortSet(1)));
end

function localAssertError(fn, expectedID)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(expectedID), ...
        "Observed %s, expected %s.", ME.identifier, expectedID);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.", expectedID);
end
