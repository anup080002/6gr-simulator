function ok = testWaveformBundleRootNormalization()
%TESTWAVEFORMBUNDLEROOTNORMALIZATION Keep live state at the run root.

root = fullfile(tempdir,"sixgr_live_stage_root");
inputs = { ...
    root, ...
    fullfile(root,"air_interface"), ...
    fullfile(root,"air_interface","csv"), ...
    fullfile(root,"air_interface","reports","csv"), ...
    fullfile(root,"reports"), ...
    fullfile(root,"reports","csv"), ...
    [char(fullfile(root,"air_interface")) filesep]};
for i = 1:numel(inputs)
    actual = sixgr.truth.normalizeWaveformBundleRootRunFolder(inputs{i});
    assert(strcmp(actual,root), ...
        "Input %s resolved to %s instead of the canonical run root %s.", ...
        inputs{i},actual,root);
end

ok = true;
disp("WAVEFORM_BUNDLE_ROOT_NORMALIZATION_PASS");
end
