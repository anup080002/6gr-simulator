function ok = testLLSQualificationStatusSeparation()
%TESTLLSQUALIFICATIONSTATUSSEPARATION Lifecycle and publication are distinct.

setup6GRSimToolkit("Verbose", false);

filesystem = llsRootGateFixture("pass");
sixgr.truth.evaluateLLSRuntimeTruthContract( ...
    filesystem.RunFolder, filesystem.ScenarioConfig, filesystem.InternalConfig);
status = localStatus(filesystem);
assert(logical(status.ExecutionCompleted(1)) && string(status.ExecutionStatus(1)) == "PASS");
assert(logical(status.ScenarioObjectivePassed(1)) && ...
    string(status.ScenarioObjectiveStatus(1)) == "PASS");
assert(logical(status.RuntimeTruthContractPassed(1)) && ...
    string(status.RuntimeTruthContractStatus(1)) == "PASS");
assert(logical(status.StandardsConformancePassed(1)) && ...
    string(status.StandardsConformanceStatus(1)) == "PASS");
assert(logical(status.PublicationQualified(1)) && ...
    string(status.PublicationQualificationStatus(1)) == "PASS");
assert(~logical(status.BrowserPublicationRequired(1)) && ...
    ~logical(status.BrowserPublished(1)) && ...
    string(status.BrowserPublicationStatus(1)) == "NOT_APPLICABLE");

web = llsRootGateFixture("pass");
web.ScenarioConfig = sixgr.util.structSet(web.ScenarioConfig, ...
    "output.backend", "mysql_web");
web.ScenarioConfig = sixgr.util.structSet(web.ScenarioConfig, ...
    "output.persist_to_database", true);
sixgr.truth.evaluateLLSRuntimeTruthContract( ...
    web.RunFolder, web.ScenarioConfig, web.InternalConfig);
missing = localStatus(web);
assert(logical(missing.ExecutionCompleted(1)));
assert(logical(missing.BrowserPublicationRequired(1)) && ...
    ~logical(missing.BrowserPublished(1)) && ...
    string(missing.BrowserPublicationStatus(1)) == "NOT_EVALUATED");
assert(~logical(missing.PublicationQualified(1)) && ~logical(missing.ResultOk(1)));

receiptDir = fullfile(web.RunFolder, "published");
mkdir(receiptDir);
receipt = struct( ...
    "SchemaName", "sixgr.browser_publication_receipt", ...
    "SchemaVersion", "1.0.0", ...
    "RunID", string(web.ScenarioConfig.scenario_id), ...
    "Status", "PASS", ...
    "DatabasePersisted", true, ...
    "BrowserMaterialized", true, ...
    "MissingRequiredTableCount", 0, ...
    "MissingRequiredChartCount", 0);
sixgr.util.jsonWrite(fullfile(receiptDir, "browser_publication_receipt.json"), receipt);
sixgr.truth.evaluateLLSRuntimeTruthContract( ...
    web.RunFolder, web.ScenarioConfig, web.InternalConfig);
published = localStatus(web);
assert(logical(published.BrowserPublished(1)) && ...
    string(published.BrowserPublicationStatus(1)) == "PASS");
assert(logical(published.PublicationQualified(1)) && logical(published.ResultOk(1)));

ok = true;
fprintf("PASS testLLSQualificationStatusSeparation: execution, science, publication and browser states are independent.\n");
end

function T = localStatus(ctx)
T = readtable(fullfile(ctx.Layout.ReportCSVDir, "result_status_summary.csv"), ...
    "VariableNamingRule", "preserve");
end
