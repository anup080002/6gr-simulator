function ok = testFRCReferenceQualificationResume()
%TESTFRCREFERENCEQUALIFICATIONRESUME Exact FRC entry checkpoints are reusable.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
root = tempname;
mkdir(root);
cleanup = onCleanup(@() rmdir(root, "s")); %#ok<NASGU>

args = { ...
    "Profile", "diagnostic", ...
    "EntryIds", "dl_r_pdsch_1_1_4_fdd_awgn", ...
    "MinTransportBlocks", 1, ...
    "MaxTransportBlocks", 2, ...
    "BatchSize", 1, ...
    "MinimumBlockErrors", 0, ...
    "Verbose", false};
first = sixgr.conformance.runReferenceQualification(root, args{:});
assert(first.ResumedCount == 0 && height(first.Table) == 1, ...
    "The first FRC execution must produce, not resume, its entry row.");
assert(isstruct(first.EntryResults{1}) && ...
    string(first.EntryResults{1}.ContractVersion) == ...
    "sixgr_conformance_frc_point/v2", ...
    "A completed FRC checkpoint must retain the full execution result.");
checkpointFiles = dir(fullfile(first.CheckpointDirectory, "*.mat"));
assert(numel(checkpointFiles) == 1 && ...
    ~isfile(fullfile(root, "reports", "csv", ...
    "frc_reference_qualification.partial.csv")), ...
    ["FRC execution must retain its exact entry checkpoint and remove the " ...
    "partial CSV only after final artifacts are published."]);
checkpoint = load(fullfile(checkpointFiles(1).folder, checkpointFiles(1).name));
assert(string(checkpoint.SchemaVersion) == ...
    "sixgr.conformance.reference_checkpoint/v6" && ...
    string(checkpoint.Identity.SchemaVersion) == ...
    "sixgr.conformance.reference_checkpoint_identity/v6" && ...
    strlength(string(checkpoint.Identity.SourceStateSHA256)) == 64 && ...
    string(checkpoint.Row.SchemaVersion) == ...
    "sixgr.conformance.reference_qualification/v6", ...
    ["Checkpoint resume must bind the versioned row to the exact production " ...
    "source-byte identity, not only a dirty-worktree boolean."]);

second = sixgr.conformance.runReferenceQualification(root, args{:});
assert(second.ResumedCount == 1 && ...
    isequaln(first.Table, second.Table) && ...
    isequaln(first.EntryResults{1}.Sweep, second.EntryResults{1}.Sweep), ...
    "An identity-matched FRC checkpoint must reproduce the exact row.");

threw = false;
try
    sixgr.conformance.runReferenceQualification(root, ...
        "Profile", "diagnostic", ...
        "EntryIds", "dl_r_pdsch_1_1_4_fdd_awgn", ...
        "MinTransportBlocks", 1, ...
        "MaxTransportBlocks", 3, ...
        "BatchSize", 1, ...
        "MinimumBlockErrors", 0, ...
        "Verbose", false);
catch ME
    threw = string(ME.identifier) == ...
        "sixgr:conformance:QualificationCheckpointIdentityMismatch";
end
assert(threw, ...
    "A changed FRC sampling policy must fail closed against an old checkpoint.");

workerRoot = tempname;
mkdir(workerRoot);
workerCleanup = onCleanup(@() rmdir(workerRoot, "s")); %#ok<NASGU>
entrySampling = struct("entry_id", "dl_r_pdsch_1_1_4_fdd_awgn", ...
    "parallel_workers", 1, "channel_chunk_slots", 0, ...
    "seed", 48104, ...
    "min_transport_blocks", 1, ...
    "max_transport_blocks", 1, "batch_size", 1);
workerRun = sixgr.conformance.runReferenceQualification(workerRoot, ...
    "Profile", "diagnostic", ...
    "EntryIds", "dl_r_pdsch_1_1_4_fdd_awgn", ...
    "EntrySampling", entrySampling, ...
    "ParallelWorkers", 4, "MinimumBlockErrors", 0, "Verbose", false);
assert(workerRun.EntryResults{1}.PointDetails{1}.ParallelWorkers == 1 && ...
    ~workerRun.EntryResults{1}.PointDetails{1}.ParallelExecution && ...
    workerRun.EntryResults{1}.PointDetails{1}.ChannelChunkSlots == 0, ...
    ["Per-entry parallel_workers must override the global worker count " ...
    "and reach the actual FRC waveform runner."]);
assert(workerRun.EntryResults{1}.Options.Seed == 48104 && ...
    workerRun.Table.ExperimentSeed == 48104, ...
    "Per-entry seed must override the global seed and reach persisted evidence.");
ok = true;
end
