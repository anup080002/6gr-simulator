function ok = testFRCReferenceQualificationResume()
%TESTFRCREFERENCEQUALIFICATIONRESUME Exact FRC entry checkpoints are reusable.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
root = tempname;
mkdir(root);
cleanup = onCleanup(@() rmdir(root, "s")); %#ok<NASGU>

args = { ...
    "Profile", "diagnostic", ...
    "EntryIds", "dl_r_pdsch_1_1_4_fdd_awgn", ...
    "MinTransportBlocks", 1, ...
    "MaxTransportBlocks", 2, ...
    "BatchSize", 1, ...
    "MinimumBlockErrors", 0, ...
    "Verbose", false};
first = sixgr.conformance.runReferenceQualification(root, args{:});
assert(first.ResumedCount == 0 && height(first.Table) == 1, ...
    "The first FRC execution must produce, not resume, its entry row.");
checkpointFiles = dir(fullfile(first.CheckpointDirectory, "*.mat"));
assert(numel(checkpointFiles) == 1 && ...
    isfile(fullfile(root, "reports", "csv", ...
    "frc_reference_qualification.partial.csv")), ...
    "FRC execution must atomically publish one entry checkpoint and partial CSV.");

second = sixgr.conformance.runReferenceQualification(root, args{:});
assert(second.ResumedCount == 1 && ...
    isequaln(first.Table, second.Table), ...
    "An identity-matched FRC checkpoint must reproduce the exact row.");

threw = false;
try
    sixgr.conformance.runReferenceQualification(root, ...
        "Profile", "diagnostic", ...
        "EntryIds", "dl_r_pdsch_1_1_4_fdd_awgn", ...
        "MinTransportBlocks", 1, ...
        "MaxTransportBlocks", 3, ...
        "BatchSize", 1, ...
        "MinimumBlockErrors", 0, ...
        "Verbose", false);
catch ME
    threw = string(ME.identifier) == ...
        "sixgr:conformance:QualificationCheckpointIdentityMismatch";
end
assert(threw, ...
    "A changed FRC sampling policy must fail closed against an old checkpoint.");
ok = true;
end
