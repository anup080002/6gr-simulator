function ok = testPDSCHConfigMaterializerNoMutation()
%TESTPDSCHCONFIGMATERIALIZERNOMUTATION One-way assignment adapter contract.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
vectors = readtable(fullfile(PDSCHPhaseTestSupport.vectorRoot(), ...
    "pdsch_scheduling_assignment_test_vectors.csv"), ...
    "TextType", "string", "VariableNamingRule", "preserve");
row = table2struct(vectors(vectors.CaseID == "ASSIGN-001", :));
[assignment, observedError] = PDSCHPhaseTestSupport.assignmentFromVector(row);
assert(strlength(observedError) == 0);
before = assignment.toStruct();

reference = struct( ...
    "NID", 42, ...
    "DMRSConfigurationType", 1, ...
    "DMRSTypeAPosition", 2, ...
    "DMRSAdditionalPosition", 1, ...
    "DMRSLength", 1, ...
    "NumCDMGroupsWithoutData", 1, ...
    "NIDNSCID", 42, ...
    "NSCID", 0, ...
    "EnablePTRS", false);
pdsch = sixgr.pdsch.PDSCHConfigMaterializer.fromAssignment( ...
    assignment, reference);
assert(isequal(double(pdsch.PRBSet), before.PRBSetCarrierRelative));
assert(isequal(double(pdsch.SymbolAllocation), before.SymbolAllocation));
assert(pdsch.NumLayers == before.NumLayers);
assert(pdsch.RNTI == before.RNTI);
assert(strcmpi(pdsch.Modulation, before.ModulationPerCodeword(1)));
assert(isequaln(before, assignment.toStruct()), ...
    "Materializing nrPDSCHConfig mutated the scheduling assignment.");

badReference = rmfield(reference, "NIDNSCID");
localAssertError(@() sixgr.pdsch.PDSCHConfigMaterializer.fromAssignment( ...
    assignment, badReference), ...
    "sixgr:pdsch:IncompleteReferenceSignalConfiguration");
assert(testPDSCHCompatibilityFacadeDelegation(), ...
    "The compatibility façade did not delegate to the canonical chain.");
fprintf("PDSCH config materializer: immutable one-way adapter passed.\\n");
ok = true;
end

function localAssertError(fn, id)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(id));
    return;
end
error("testPDSCHConfigMaterializerNoMutation:MissingError", "Expected %s.", id);
end
