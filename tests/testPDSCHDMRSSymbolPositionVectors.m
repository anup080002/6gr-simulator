function ok = testPDSCHDMRSSymbolPositionVectors()
%TESTPDSCHDMRSSYMBOLPOSITIONVECTORS Execute all frozen DM-RS position rows.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
vectors = readPDSCHVectorTable("pdsch_dmrs_test_vectors.csv");
golden = readPDSCHVectorTable( ...
    "expected_pdsch_dmrs_symbol_positions.csv");
assert(height(vectors) == 175 && height(golden) == 175, ...
    "The complete 175-row DM-RS position matrix is mandatory.");
assert(isequal(vectors.CaseID, golden.CaseID), ...
    "DM-RS input and expected case IDs differ.");

passCount = 0;
negativeCount = 0;
for i = 1:height(vectors)
    request = localRequest(vectors(i, :));
    before = request;
    expectedSymbols = pdschVectorDecodeIntegers( ...
        golden.ExpectedDMRSSymbols(i));
    expectedCount = str2double(golden.ExpectedDMRSSymbolCount(i));
    expectedStatus = golden.Status(i);
    expectedToken = golden.ExpectedError(i);

    oracle = sixgr.pdsch.oracle.DMRSTableSpec. ...
        symbolPositions(request);
    assert(oracle.Status == expectedStatus, ...
        "Independent status mismatch for %s.", vectors.CaseID(i));
    assert(oracle.ErrorToken == expectedToken, ...
        "Independent error mismatch for %s.", vectors.CaseID(i));
    assert(isequal(oracle.Symbols, expectedSymbols), ...
        "Independent DM-RS symbols mismatch for %s.", vectors.CaseID(i));
    assert(oracle.Count == expectedCount, ...
        "Independent DM-RS count mismatch for %s.", vectors.CaseID(i));

    if expectedStatus == "PASS"
        actual = sixgr.pdsch.PDSCHDMRSValidator. ...
            validateConfiguration(request);
        assert(actual.OriginalUnchanged && isequaln(request, before), ...
            "Production DM-RS validation mutated %s.", vectors.CaseID(i));
        assert(isequal(actual.SymbolPositions, expectedSymbols), ...
            "Production DM-RS symbols mismatch for %s.", vectors.CaseID(i));
        assert(actual.SymbolCount == expectedCount, ...
            "Production DM-RS count mismatch for %s.", vectors.CaseID(i));
        passCount = passCount + 1;
    else
        expectedID = "sixgr:pdsch:" + expectedToken;
        localAssertError(@() sixgr.pdsch.PDSCHDMRSValidator. ...
            validateConfiguration(request), expectedID);
        assert(isequaln(request, before), ...
            "Rejected DM-RS validation mutated %s.", vectors.CaseID(i));
        negativeCount = negativeCount + 1;
    end
end
assert(passCount == 133 && negativeCount == 42, ...
    "Unexpected DM-RS positive/negative execution counts.");

% Regression: for mapping A, TS 38.211 table l_d is the allocation
% end relative to the slot, not merely the allocation duration.
nonzeroStart = struct( ...
    "MappingType","A","DMRSLength",1, ...
    "PDSCHStartSymbol",2,"PDSCHDurationLd",12, ...
    "DMRSTypeAPosition",2,"DMRSAdditionalPosition",2, ...
    "DMRSConfigurationType",1,"DMRSMultiplexing","basic", ...
    "DMRSPortSet",0);
expectedNonzeroStart = [2 7 11];
actualNonzeroStart = sixgr.pdsch.PDSCHDMRSValidator. ...
    validateConfiguration(nonzeroStart);
oracleNonzeroStart = sixgr.pdsch.oracle.DMRSTableSpec. ...
    symbolPositions(nonzeroStart);
carrier = nrCarrierConfig;
carrier.NSizeGrid = 4;
carrier.SubcarrierSpacing = 30;
pdsch = nrPDSCHConfig;
pdsch.PRBSet = 0:3;
pdsch.SymbolAllocation = [2 12];
pdsch.MappingType = "A";
pdsch.NumLayers = 1;
pdsch.Modulation = "QPSK";
pdsch.DMRS.DMRSConfigurationType = 1;
pdsch.DMRS.DMRSTypeAPosition = 2;
pdsch.DMRS.DMRSAdditionalPosition = 2;
pdsch.DMRS.DMRSLength = 1;
pdsch.DMRS.DMRSPortSet = 0;
subscripts = nrPDSCHDMRSIndices(carrier,pdsch, ...
    "IndexStyle","subscript","IndexBase","0based");
toolboxSymbols = unique(double(subscripts(:,2))).';
assert(isequal(actualNonzeroStart.SymbolPositions,expectedNonzeroStart) ...
    && isequal(oracleNonzeroStart.Symbols,expectedNonzeroStart) ...
    && isequal(toolboxSymbols,expectedNonzeroStart), ...
    "Mapping-A nonzero-start l_d regression failed: expected " + ...
    "[2 7 11] from start=2,duration=12.");
ok = true;
end

function request = localRequest(row)
request = struct( ...
    "MappingType", row.MappingType(1), ...
    "DMRSLength", str2double(row.DMRSLength(1)), ...
    "PDSCHStartSymbol", str2double(row.PDSCHStartSymbol(1)), ...
    "PDSCHDurationLd", str2double(row.PDSCHDurationLd(1)), ...
    "DMRSTypeAPosition", str2double(row.DMRSTypeAPosition(1)), ...
    "DMRSAdditionalPosition", ...
        str2double(row.DMRSAdditionalPosition(1)), ...
    "DMRSConfigurationType", ...
        str2double(row.DMRSConfigurationType(1)), ...
    "DMRSMultiplexing", row.DMRSMultiplexing(1), ...
    "DMRSPortSet", pdschVectorDecodeIntegers(row.DMRSPortSet(1)));
end

function localAssertError(fn, expectedID)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(expectedID), ...
        "Observed %s, expected %s.", ME.identifier, expectedID);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.", expectedID);
end
