function ok = testPDSCHNoNoiseRoundTrip()
%TESTPDSCHNONOISEROUNDTRIP Explicit TB-to-LLR-to-TB coding regressions.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
rng(21451, "twister");
cases = [ ...
    struct("A",24,    "R",0.50, "Mod","QPSK",  "Qm",2, "NL",1, "RV",0), ...
    struct("A",384,   "R",0.30, "Mod","16QAM", "Qm",4, "NL",2, "RV",1), ...
    struct("A",4096,  "R",0.55, "Mod","64QAM", "Qm",6, "NL",1, "RV",2), ...
    struct("A",10000, "R",0.70, "Mod","256QAM","Qm",8, "NL",2, "RV",3)];

bitErrors = 0;
multiCB = 0;
for i = 1:numel(cases)
    cfg = cases(i);
    seg = sixgr.pdsch.oracle.LDPCSegmentationSpec(cfg.A, cfg.R);
    quantum = cfg.Qm * cfg.NL;
    G = quantum * ceil(seg.MotherCodeLength * seg.NumCodeBlocks / quantum);
    plan = sixgr.pdsch.DLSCHCodingPlan.resolve( ...
        "TransportBlockSize", cfg.A, ...
        "TargetCodeRate", cfg.R, ...
        "RateMatchedBitCount", G, ...
        "RV", cfg.RV, ...
        "Modulation", cfg.Mod, ...
        "NumLayers", cfg.NL);
    bits = int8(randi([0 1], cfg.A, 1));
    encoded = sixgr.pdsch.DLSCHEncoder(bits, plan);
    llr = 40 * (1 - 2 * double(encoded.RateMatchedBits));
    decoded = sixgr.pdsch.DLSCHDecoder( ...
        llr, "CodingPlan", plan, "MaxIterations", 12);
    errors = nnz(decoded.TransportBlock(:) ~= bits(:));
    bitErrors = bitErrors + errors;
    assert(decoded.CRCPass && ~decoded.CRCError && errors == 0, ...
        "Case %d no-noise round trip failed with %d bit errors.", i, errors);
    assert(string(decoded.CodingPlanID) == string(encoded.CodingPlanID), ...
        "Case %d TX/RX coding-plan identity mismatch.", i);
    multiCB = multiCB + (double(plan.NumCodeBlocks) > 1);
end

assert(multiCB >= 1, "No-noise suite must include a multi-code-block TB.");
localPositionAwareHARQ();
fprintf("PDSCH no-noise DL-SCH: %d/%d CRC pass, total bit errors=%d, multi-CB=%d\n", ...
    numel(cases), numel(cases), bitErrors, multiCB);
ok = true;
end

function localPositionAwareHARQ()
A = 384;
common = { ...
    "TransportBlockSize", A, ...
    "TargetCodeRate", 0.5, ...
    "RateMatchedBitCount", 3000, ...
    "Modulation", "QPSK", ...
    "NumLayers", 1};
plan0 = sixgr.pdsch.DLSCHCodingPlan.resolve(common{:}, "RV", 0);
plan2 = sixgr.pdsch.DLSCHCodingPlan.resolve(common{:}, "RV", 2);
bits = int8(mod((0:(A - 1)).', 5) < 2);
encoded0 = sixgr.pdsch.DLSCHEncoder(bits, plan0);
encoded2 = sixgr.pdsch.DLSCHEncoder(bits, plan2);
decoded0 = sixgr.pdsch.DLSCHDecoder( ...
    30 * (1 - 2 * double(encoded0.RateMatchedBits)), ...
    "CodingPlan", plan0, "HARQKey", "roundtrip-cw0");
decoded2 = sixgr.pdsch.DLSCHDecoder( ...
    30 * (1 - 2 * double(encoded2.RateMatchedBits)), ...
    "CodingPlan", plan2, ...
    "PriorRecoveredLLR", decoded0, ...
    "HARQKey", "roundtrip-cw0");
assert(decoded2.HARQCombineInfo.Applied && decoded2.CRCPass && ...
    isequal(decoded2.TransportBlock, bits), ...
    "RV0-to-RV2 position-aware HARQ round trip failed.");
end
