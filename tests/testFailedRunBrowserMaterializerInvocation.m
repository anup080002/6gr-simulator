function ok = testFailedRunBrowserMaterializerInvocation()
%TESTFAILEDRUNBROWSERMATERIALIZERINVOCATION Preserve failure recovery inputs.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
sourcePath = which("sixgr.lls6g.runners.runSingle");
assert(strlength(string(sourcePath)) > 0, ...
    "Production runSingle source was not found.");
sourceText = string(fileread(sourcePath));
assert(count(sourceText, ...
    "localMaterializeBrowserContractArtifacts(runFolder)") >= 2, ...
    ['Both normal finalization and failed-run recovery must pass the active ' ...
    'run folder to browser-contract materialization.']);
assert(~contains(sourceText, ...
    "contractMaterialization = localMaterializeBrowserContractArtifacts();"), ...
    ['Failed-run recovery must not invoke a one-input materializer without ' ...
    'its active run-folder argument.']);
ok = true;
end
