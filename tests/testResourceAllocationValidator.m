function localVerifyFDDDirectionalGridIdentity()
fdd = sixgr.phy.frame.FDDCarrierContexts.create( ...
    "CellID", 9, "DLCCID", 0, "ULCCID", 1, ...
    "DLCenterFrequencyHz", 3.50e9, ...
    "ULCenterFrequencyHz", 3.60e9, ...
    "SubcarrierSpacingKHz", 15, ...
    "DLNumRB", 24, "ULNumRB", 24);
wrong = sixgr.phy.frame.ResourceAllocationValidator.makeAllocation( ...
    "PDSCH", "DL", "StartSymbol", 2, "NumSymbols", 10, ...
    "MappingType", "A", "StartRB", 0, "NumRB", 4, ...
    "GridID", fdd.Uplink.GridID);
wrongBefore = wrong;
result = sixgr.phy.frame.ResourceAllocationValidator.validate(wrong, fdd);
assert(~result.ActualValid && ...
    result.ErrorID == "sixgr:phy:frame:FDDGridContextMismatch" && ...
    result.ReasonCode == "fdd_grid_context_mismatch" && ...
    result.OriginalUnchanged && isequaln(wrong, wrongBefore), ...
    "A DL allocation carrying the UL FDD GridID must fail unchanged.");

correct = wrong;
correct.GridID = fdd.Downlink.GridID;
result = sixgr.phy.frame.ResourceAllocationValidator.validate(correct, fdd);
assert(result.ActualValid && ...
    result.Allocation.GridID == fdd.Downlink.GridID, ...
    "A DL allocation with the directional FDD GridID must pass.");
end

function allocation = localAllocation(row)
mapping = "";
if any(row.Channel == ["PDSCH","PUSCH"])
    mapping = "A";
end
start = [];
count = [];
if isfinite(row.StartSymbol)
    start = row.StartSymbol;
end
if isfinite(row.NumSymbols)
    count = row.NumSymbols;
end
allocation = sixgr.phy.frame.ResourceAllocationValidator.makeAllocation( ...
    row.Channel, row.Direction, "CCID", 0, "BWPID", 0, ...
    "AbsoluteSlot", 0, "StartSymbol", start, "NumSymbols", count, ...
    "MappingType", mapping, "StartRB", 0, "NumRB", 1, ...
    "TestID", row.TestID);
end

function [state, conflict] = localState(symbolMap, decisions)
map = char(symbolMap);
resolved = strings(1, numel(map));
resolved(map == 'D') = "D";
resolved(map == 'U') = "U";
resolved(map == 'F') = "UNRESOLVED_FLEX";
state = struct("DuplexMode", "TDD", ...
    "CommonDirection", map, "DedicatedDirection", strings(size(map)), ...
    "SymbolDirection", map, "ResolvedDirection", resolved, ...
    "ResolutionSource", strings(size(map)), ...
    "AllocationOwner", strings(size(map)));
conflict = "";
decisions = strtrim(string(decisions));
if ismissing(decisions) || any(decisions == ["","none","unresolved"])
    return;
end
parts = split(decisions, ";");
for i = 1:numel(parts)
    token = split(parts(i), ":");
    direction = token(1);
    bounds = split(token(2), "-");
    first = str2double(bounds(1));
    last = first;
    if numel(bounds) == 2
        last = str2double(bounds(2));
    end
    request = struct("AbsoluteSlot", 0, "StartSymbol", first, ...
        "NumSymbols", last - first + 1, "Direction", direction, ...
        "Channel", "vector_runtime", "DecisionSource", "test_vector");
    try
        state = sixgr.phy.frame.FlexibleSymbolAllocator.allocate(state, request);
    catch ME
        if string(ME.identifier) == ...
                "sixgr:phy:frame:ConflictingFlexibleSymbolResolution"
            conflict = "conflicting_flexible_symbol_resolution";
            return;
        end
        rethrow(ME);
    end
end
end

function state = localFixedState(direction, nSymbols)
if nargin < 2
    nSymbols = 14;
end
state = struct("DuplexMode", "TDD", ...
    "SymbolsPerSlot", double(nSymbols), ...
    "CommonDirection", repmat(direction, 1, nSymbols), ...
    "DedicatedDirection", strings(1, nSymbols), ...
    "SymbolDirection", repmat(direction, 1, nSymbols), ...
    "ResolvedDirection", repmat(string(direction), 1, nSymbols), ...
    "ResolutionSource", strings(1, nSymbols), ...
    "AllocationOwner", strings(1, nSymbols));
end

function localAssertError(f, id)
try
    f();
catch ME
    assert(string(ME.identifier) == string(id), ...
        "Observed %s, expected %s.", ME.identifier, id);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", "Expected %s.", id);
end
