function localVerifyExactULControlRandomAccessAndRS()
carrier = nrCarrierConfig;
carrier.NSizeGrid = 52;
carrier.SubcarrierSpacing = 15;
carrier.NCellID = 11;
carrier.NFrame = 0;
carrier.NSlot = 0;

pusch = nrPUSCHConfig;
pusch.PRBSet = 0:9;
pusch.SymbolAllocation = [2 10];
pusch.MappingType = "B";
pusch.Modulation = "QPSK";
puschResult = sixgr.phy.frame.ChannelAllocationMaterializer. ...
    materializePUSCH(carrier, pusch, ...
    "GridID", "ul_exact_grid", "TestID", "PUSCH_EXACT");
[directPUSCH, ~] = nrPUSCHIndices(carrier, pusch, ...
    "IndexStyle", "index", "IndexBase", "1based");
directPUSCHDMRS = nrPUSCHDMRSIndices(carrier, pusch, ...
    "IndexStyle", "index", "IndexBase", "1based");
assert(isequal(sort(puschResult.Data.Indices1Based), ...
        sort(unique(double(directPUSCH(:))))) && ...
    isequal(sort(puschResult.DMRS.Indices1Based), ...
        sort(unique(double(directPUSCHDMRS(:))))) && ...
    puschResult.Exact && ~puschResult.FallbackUsed, ...
    "PUSCH canonical allocation must equal the exact Toolbox indices.");
stateUL = localFixedState('U');
validatedPUSCH = sixgr.phy.frame.ResourceAllocationValidator.validate( ...
    puschResult.Allocation, stateUL);
assert(validatedPUSCH.ActualValid && ...
    isequal(sort(validatedPUSCH.Occupancy.REKey), ...
        sort(puschResult.ActualREKeys)), ...
    "PUSCH exact coordinates must survive canonical validation unchanged.");

pucch = nrPUCCH1Config;
pucch.PRBSet = 20;
pucch.SymbolAllocation = [10 4];
pucch.FrequencyHopping = "neither";
pucchResult = sixgr.phy.frame.ChannelAllocationMaterializer. ...
    materializePUCCH(carrier, pucch, ...
    "GridID", "ul_exact_grid", "TestID", "PUCCH_EXACT");
[directPUCCH, ~] = nrPUCCHIndices(carrier, pucch);
directPUCCHDMRS = nrPUCCHDMRSIndices(carrier, pucch);
assert(isequal(sort(pucchResult.Data.Indices1Based), ...
        sort(unique(double(directPUCCH(:))))) && ...
    isequal(sort(pucchResult.DMRS.Indices1Based), ...
        sort(unique(double(directPUCCHDMRS(:))))) && ...
    pucchResult.Exact, ...
    "PUCCH canonical allocation must equal the exact Toolbox indices.");

rsResult = sixgr.phy.frame.ChannelAllocationMaterializer. ...
    materializeReferenceSignal(carrier, "PUSCH_DMRS", pusch, ...
    "GridID", "ul_exact_grid", "TestID", "PUSCH_DMRS_RS");
assert(rsResult.ToolboxSource == "nrPUSCHDMRSIndices" && ...
    isequal(sort(rsResult.Resources.Indices1Based), ...
        sort(puschResult.DMRS.Indices1Based)), ...
    "Reference-signal reservation must be backed by exact Toolbox indices.");

[prachCarrier, prach] = localActivePRACH();
prachResult = sixgr.phy.frame.ChannelAllocationMaterializer. ...
    materializePRACH(prachCarrier, prach, ...
    "GridID", "prach_exact_grid", "TestID", "PRACH_EXACT");
[directPRACH, ~] = nrPRACHIndices(prachCarrier, prach, ...
    "IndexStyle", "subscript", "IndexBase", "0based");
if size(directPRACH, 2) == 2
    directPRACH(:, 3) = 0;
end
assert(isequal(sortrows(prachResult.ActualCoordinates0Based), ...
        sortrows(unique(double(directPRACH), "rows"))) && ...
    prachResult.Exact && ~prachResult.FallbackUsed, ...
    "PRACH canonical allocation must equal exact carrier-grid Toolbox subscripts.");
end

