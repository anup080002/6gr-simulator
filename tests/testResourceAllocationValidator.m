function ok = testResourceAllocationValidator()
%TESTRESOURCEALLOCATIONVALIDATOR Execute all supplied allocation vectors.

setup6GRSimToolkit("Verbose", false);
base = fullfile(fileparts(mfilename("fullpath")), "vectors", "frame_grid");
vectors = readtable(fullfile(base, "frame_allocation_test_vectors.csv"), ...
    "TextType", "string", "VariableNamingRule", "preserve");
golden = readtable(fullfile(base, "expected_allocation_legality.csv"), ...
    "TextType", "string", "VariableNamingRule", "preserve");
assert(isequal(vectors.TestID, golden.TestID), ...
    "Allocation vector/golden TestID order differs.");

for i = 1:height(vectors)
    row = vectors(i, :);
    [state, conflict] = localState(row.SymbolMap, row.FlexResolution);
    if strlength(conflict) > 0
        actualValid = false;
        reason = conflict;
    else
        allocation = localAllocation(row);
        before = allocation;
        result = sixgr.phy.frame.ResourceAllocationValidator.validate( ...
            allocation, state);
        actualValid = result.ActualValid;
        reason = result.ReasonCode;
        assert(isequaln(allocation, before), ...
            "%s allocation input was mutated.", row.TestID);
    end
    expectedValid = upper(row.ExpectedValid) == "TRUE";
    assert(actualValid == expectedValid, ...
        "%s legality mismatch.", row.TestID);
    assert(reason == row.ExpectedReasonCode, ...
        "%s returned %s, expected %s.", ...
        row.TestID, reason, row.ExpectedReasonCode);
end

localAssertError(@() ...
    sixgr.phy.frame.ResourceAllocationValidator.decodeSLIV(999, 14), ...
    "sixgr:phy:frame:InvalidSLIV");
localVerifyCanonicalSymbolsPerSlotRequired();
localVerifyPinnedTDRACatalog();
localVerifyStrictProductionTDRAResolution();
localVerifyMissingAllocationsFailClosed();
localVerifyExactULControlRandomAccessAndRS();
localVerifyFDDDirectionalGridIdentity();
ok = true;
end

function localVerifyCanonicalSymbolsPerSlotRequired()
allocation = sixgr.phy.frame.ResourceAllocationValidator.makeAllocation( ...
    "PDSCH", "DL", "StartSymbol", 0, "NumSymbols", 12, ...
    "MappingType", "A", "StartRB", 0, "NumRB", 4);
missing = sixgr.phy.frame.ResourceAllocationValidator.validate( ...
    allocation, struct());
assert(~missing.ActualValid && ...
    missing.ErrorID == "sixgr:phy:frame:MissingSymbolsPerSlot", ...
    "Allocation validation must not assume normal-CP 14 symbols.");

state = localFixedState('D', 12);
resolved = sixgr.phy.frame.ResourceAllocationValidator.validate( ...
    allocation, state);
assert(resolved.ActualValid && ...
    resolved.Allocation.SymbolsPerSlot == 12 && ...
    resolved.Allocation.SLIV == ...
        sixgr.phy.frame.ResourceAllocationValidator.encodeSLIV(0, 12, 12) && ...
    resolved.ReasonCode == ...
        "preserve_explicit_full_slot_pdsch_no_auto_shift", ...
    "Allocation validation must use the supplied 12-symbol canonical context.");
end

function localVerifyPinnedTDRACatalog()
T = sixgr.phy.frame.TimeDomainResourceAllocationCatalog.table();
expected = table( ...
    ["PDSCH_DEFAULT_A_NCP_R1_DMRS2"; ...
     "PDSCH_DEFAULT_A_NCP_R6_DMRS2"; ...
     "PDSCH_DEFAULT_B_NCP_R6_DMRS2"; ...
     "PDSCH_DEFAULT_B_NCP_R14_DMRS2"; ...
     "PUSCH_DEFAULT_A_NCP_R1_MU0"; ...
     "PUSCH_DEFAULT_A_NCP_R4_MU0"], ...
    ["PDSCH";"PDSCH";"PDSCH";"PDSCH";"PUSCH";"PUSCH"], ...
    [1;6;6;14;1;4], ["A";"B";"B";"A";"A";"B"], ...
    [0;0;1;0;NaN;NaN], [NaN;NaN;NaN;NaN;1;1], ...
    [2;9;2;2;0;2], [12;4;2;12;14;10], ...
    [53;51;16;53;27;81], ...
    'VariableNames', {'ID','Channel','RowIndex','MappingType', ...
    'K0','K2','StartSymbol','NumSymbols','SLIV'});
assert(height(T) == height(expected), ...
    "The selected TDRA anchor must contain exactly the pinned rows.");
for i = 1:height(expected)
    row = T(i, :);
    assert(row.ID == expected.ID(i) && ...
        row.Channel == expected.Channel(i) && ...
        row.RowIndex == expected.RowIndex(i) && ...
        row.MappingType == expected.MappingType(i) && ...
        isequaln(row.K0, expected.K0(i)) && ...
        isequaln(row.K2, expected.K2(i)) && ...
        row.StartSymbol == expected.StartSymbol(i) && ...
        row.NumSymbols == expected.NumSymbols(i) && ...
        row.SLIV == expected.SLIV(i) && ...
        row.SpecificationVersion == "V18.8.0" && ...
        contains(row.StandardReference, row.TableNumber), ...
        "Pinned TS 38.214 TDRA row %s differs from its golden data.", ...
        expected.ID(i));
    raw = struct("TDRAID", row.ID, "Channel", row.Channel);
    if isfinite(row.DMRSTypeAPosition)
        raw.DMRSTypeAPosition = row.DMRSTypeAPosition;
    end
    if isfinite(row.Mu)
        raw.Mu = row.Mu;
    end
    resolved = sixgr.phy.frame.ResourceAllocationValidator. ...
        resolveTDRA(raw, 14);
    assert(resolved.TDRAID == row.ID && ...
        resolved.StartSymbol == row.StartSymbol && ...
        resolved.NumSymbols == row.NumSymbols && ...
        resolved.MappingType == row.MappingType && ...
        resolved.SLIV == row.SLIV && ...
        isequaln(resolved.K0, row.K0) && ...
        isequaln(resolved.K2, row.K2), ...
        "Catalog TDRA %s did not survive production resolution.", row.ID);
end
assert(any(T.Channel == "PDSCH" & T.MappingType == "A") && ...
    any(T.Channel == "PDSCH" & T.MappingType == "B") && ...
    any(T.Channel == "PUSCH" & T.MappingType == "A") && ...
    any(T.Channel == "PUSCH" & T.MappingType == "B"), ...
    "The selected catalog must execute DL and UL mapping types A and B.");

localAssertError(@() ...
    sixgr.phy.frame.ResourceAllocationValidator.resolveTDRA( ...
    struct("TDRAID", "PDSCH_DEFAULT_B_NCP_R6_DMRS2", ...
    "Channel", "PDSCH", "StartSymbol", 3), 14), ...
    "sixgr:phy:frame:InconsistentTDRA");
localAssertError(@() ...
    sixgr.phy.frame.TimeDomainResourceAllocationCatalog.resolve( ...
    "PUSCH_DEFAULT_A_NCP_R1_MU0", "Mu", 1), ...
    "sixgr:phy:frame:TDRANumerologyMismatch");
localAssertError(@() ...
    sixgr.phy.frame.TimeDomainResourceAllocationCatalog.resolve( ...
    "NOT_A_STANDARD_ROW"), ...
    "sixgr:phy:frame:UnknownTDRACatalogID");
end

