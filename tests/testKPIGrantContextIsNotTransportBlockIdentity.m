function ok = testKPIGrantContextIsNotTransportBlockIdentity()
%TESTKPIGRANTCONTEXTISNOTTRANSPORTBLOCKIDENTITY
% Reusing one frozen grant context for distinct new-data TBs must not make
% later successful TBs look like duplicate HARQ deliveries.

setup6GRSimToolkit("Verbose", false);

raw = struct();
raw.DL = localDirectionTable("DL");
raw.UL = localDirectionTable("UL");

out = sixgr.kpi.reconstructLLSKPISummaryFromRaw(raw, "StrictMode", true);
for direction = ["DL", "UL"]
    trace = out.("HARQDeliveryTrace" + direction);
    summary = out.ReconstructionSummary( ...
        string(out.ReconstructionSummary.KPIName) == ...
        direction + "_TB_Delivery_Goodput_Mbps", :);
    assert(height(trace) == 3, "%s trace must retain all three attempts.", direction);
    assert(numel(unique(string(trace.TransportBlockId))) == 3, ...
        "%s distinct new-data TBs must receive distinct lifecycle identities.", direction);
    assert(sum(logical(trace.FirstSuccessDelivery)) == 3, ...
        "%s must count every successful new-data TB as a first delivery.", direction);
    assert(~any(logical(trace.DuplicateDelivery)), ...
        "%s must not deduplicate distinct new-data TBs sharing a grant context.", direction);
    assert(abs(double(summary.NumeratorValue(1)) - 3000) < 1e-9, ...
        "%s goodput numerator must contain all three successful TBs.", direction);
    assert(double(summary.DuplicateDeliveryCount(1)) == 0, ...
        "%s duplicate-delivery count must remain zero.", direction);
end

ok = true;
end

function T = localDirectionTable(direction)
n = 3;
T = table( ...
    repmat(string(direction), n, 1), ones(n, 1), true(n, 1), zeros(n, 1), ...
    repmat(1000, n, 1), repmat(1000, n, 1), repmat(1000, n, 1), ...
    ones(n, 1), (1:n).', ones(n, 1), zeros(n, 1), ones(n, 1), ...
    true(n, 1), false(n, 1), repmat("shared_frozen_grant_context", n, 1), ...
    ones(n, 1), (1:n).', ...
    'VariableNames', {'Direction','Goodput_Mbps','CRCPass','BitErrors','BitsCompared', ...
    'TBSize_bits','GoodBits','Frame','Slot','UEIndex','RV','NDI','NewDataFlag', ...
    'RetransmissionFlag','GrantContextId','AirInterfaceObservation_ms','TrialId'});
end
