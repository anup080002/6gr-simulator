function ok = testPUCCHFixedFormatValidation()
%TESTPUCCHFIXEDFORMATVALIDATION Guard fixed-format PUCCH anchors.

setup6GRSimToolkit("Verbose", false);

cfg = sixgr.config.defaultConfig();
cfg.run.useMex = false;
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.snr_dB = 35;
cfg.phy.pucch.enable = true;
cfg.phy.pucch.format = 2;
cfg.phy.rnti = 320;
cfg.run.noiseOperatingMode = "receiver_noise_figure_thermal_noise";
cfg.run.interferenceExecutionMode = "none";
cfg = sixgr.config.normalizeConfig(cfg);

uciLong = int8([1; 0; 1; 1]);
valid = sixgr.link.runPUCCHWaveformTrial(cfg, ...
    "ExpectedUCIBits", uciLong, "SNR_dB", 35, "Format", 2, ...
    "RNTI", 320, "FixedFormatValidation", true);
assert(double(valid.RequestedFormat) == 2 && double(valid.ResolvedFormat) == 2 && ...
    ~logical(valid.FormatAdapted) && logical(valid.ControlResourceValidity), ...
    "Fixed-format PUCCH validation must not mutate a valid requested format.");
assert(isfield(valid.Rx, "UCIContentMatch") && logical(valid.Rx.UCIContentMatch) && ...
    double(valid.Rx.BitErrors) == 0 && double(valid.Rx.BitsCompared) == numel(uciLong), ...
    "PUCCH_Rx must expose direct expected-vs-decoded UCI bit evidence.");

invalid = sixgr.link.runPUCCHWaveformTrial(cfg, ...
    "ExpectedUCIBits", int8([1; 0; 1; 0]), "SNR_dB", 35, "Format", 0, ...
    "RNTI", 320, "FixedFormatValidation", true);
assert(strcmpi(char(string(invalid.Status)), "FAIL") && ...
    strcmpi(char(string(invalid.FailureReason)), "pucch_fixed_format_payload_incompatible"), ...
    "Fixed-format PUCCH validation must reject incompatible payload/format pairs before waveform generation.");
assert(double(invalid.RequestedFormat) == 0 && double(invalid.ResolvedFormat) == 0 && ...
    ~logical(invalid.FormatAdapted) && ~logical(invalid.ControlResourceValidity), ...
    "Rejected fixed-format PUCCH trials must preserve requested format without silent promotion.");

legacy = sixgr.link.runPUCCHWaveformTrial(cfg, ...
    "ExpectedUCIBits", int8(1), "SNR_dB", 35, "Format", 2, ...
    "RNTI", 320, "FixedFormatValidation", false);
assert(double(legacy.RequestedFormat) == 2 && double(legacy.ResolvedFormat) == 1 && ...
    logical(legacy.FormatAdapted), ...
    "Non-fixed exploratory PUCCH trials may still disclose legacy payload-compatible format adaptation.");

ok = true;
end
