function ok=testRFSynchronizationConfigurationAuthority()
% Report-only numerical fixtures: never waveform qualification evidence.
scfg=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/fixtures/lls_result_richness.yaml');
source=scfg.toStruct();
root=fullfile(pwd,'results','lls','rf_sync_configuration', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(root);
runtime=sixgr.lls6g.buildInternalConfig(scfg,root);
assert(runtime.phy.impairments.cfoHz==40 && ...
    runtime.phy.impairments.timingOffsetSamples==16);
T=table([40;40],[40;40],[0;0],[16;16],[16;16],[0;0], ...
    'VariableNames',{'InjectedCFO_Hz','EstimatedCFO_PreCorrection_Hz', ...
    'ResidualCFO_PostCorrection_Hz','InjectedTimingOffset_samples', ...
    'EstimatedTimingOffset_PreCorrection_samples','ResidualTimingError_PostCorrection_samples'});
raw=struct('DL',T,'UL',T);
for representation=["source","runtime"]
    if representation=="source", cfg=source; else, cfg=runtime; end
    a=sixgr.analytics.writeRFInterferenceReconciliation(cfg, ...
        fullfile(root,representation),raw,struct(),struct());
    assert(all(a.Tables.CFO.ConfiguredCFO_Hz==40) && ...
        all(a.Tables.CFO.CFOEstimationRequired) && ...
        all(a.Tables.CFO.CfoConfiguredAppliedOk));
    assert(all(a.Tables.Timing.ConfiguredTimingOffset_samples==16) && ...
        all(a.Tables.Timing.TimingOffsetConfiguredAppliedOk));
end
% Explicit disabled stages are zero injections even when a saved request
% retains a nonzero setting for the next enabled experiment.
disabled=source;
disabled.impairments.cfo_enabled=false;
disabled.impairments.timing_offset_enabled=false;
identity=T; identity{:,:}=0;
identity.EstimatedCFO_PreCorrection_Hz(:)=NaN;
identity.ResidualCFO_PostCorrection_Hz(:)=NaN;
a=sixgr.analytics.writeRFInterferenceReconciliation(disabled, ...
    fullfile(root,'disabled'),struct('DL',identity,'UL',identity),struct(),struct());
assert(all(a.Tables.CFO.ConfiguredCFO_Hz==0) && ...
    ~any(a.Tables.CFO.CFOEstimationRequired) && all(a.Tables.CFO.CfoConfiguredAppliedOk));
assert(all(a.Tables.Timing.ConfiguredTimingOffset_samples==0));
% Missing or mismatched observations cannot disappear from the population.
for variant=["missing_injection","missing_estimator","missing_residual", ...
        "wrong_injection","subunit_wrong_injection","large_residual"]
    bad=T;
    switch variant
        case "missing_injection"
            bad.InjectedCFO_Hz(2)=NaN; bad.InjectedTimingOffset_samples(2)=NaN;
        case "missing_estimator"
            bad.EstimatedCFO_PreCorrection_Hz(2)=NaN;
            bad.EstimatedTimingOffset_PreCorrection_samples(2)=NaN;
        case "missing_residual"
            bad.ResidualCFO_PostCorrection_Hz(2)=NaN;
            bad.ResidualTimingError_PostCorrection_samples(2)=NaN;
        case "wrong_injection"
            bad.InjectedCFO_Hz(2)=80; bad.InjectedTimingOffset_samples(2)=32;
        case "subunit_wrong_injection"
            % These are exact execution metadata, not estimator uncertainty.
            bad.InjectedCFO_Hz(2)=40.001; bad.InjectedTimingOffset_samples(2)=16.001;
        case "large_residual"
            bad.ResidualCFO_PostCorrection_Hz(2)=4;
            bad.ResidualTimingError_PostCorrection_samples(2)=4;
    end
    a=sixgr.analytics.writeRFInterferenceReconciliation(runtime, ...
        fullfile(root,variant),struct('DL',bad,'UL',bad),struct(),struct());
    assert(~any(a.Tables.CFO.CfoConfiguredAppliedOk) && ...
        ~any(a.Tables.Timing.TimingOffsetConfiguredAppliedOk), ...
        'Incomplete/failed synchronization evidence was accepted: %s.',variant);
end
% Receiver-measured common frequency must survive independently from the
% oscillator-reference residual. A small number (or reused observation) is
% not evidence of independently qualified receiver accuracy.
observations=T;
observations.SweepPointIndex=[1;2];
observations.ConfiguredSNR_dB=[40;30];
observations.Slot=[43;43];
observations.CFOCorrectionApplied_Hz=[40;40];
observations.ResidualCFO_EstimatedPostCorrection_Hz=[0;7.25];
observations.ResidualCFOEstimateSource=["cyclic_prefix";"reference_symbol_common_re_phase_slope"];
observations.ResidualCFOEstimateDomain=repmat("receiver_measured_common_frequency_after_correction",2,1);
observations.ResidualCFOReusesAcquisitionObservation=[1;0];
observations.ResidualCFOEstimateRole=[ ...
    "same_observation_estimator_consistency_not_independent_residual"; ...
    "post_correction_estimate_independence_not_established"];
observations.TimingMetricRole=repmat("earliest_arrival_relative_alignment_not_correlation_peak_accuracy",2,1);
before=observations;
a=sixgr.analytics.writeRFInterferenceReconciliation(runtime, ...
    fullfile(root,'separate_observation_planes'),struct('DL',observations,'UL',T),struct(),struct());
assert(isequaln(observations,before));
view=a.Tables.SynchronizationObservations;
assert(height(view)==4 && isequal(view.SweepPointIndex(1:2),[1;2]) && ...
    isequal(view.ConfiguredSNR_dB(1:2),[40;30]) && all(view.Slot(1:2)==43));
assert(all(view.EstimatedTimingOffset_PreCorrection_samples==16) && ...
    all(isnan(view.RawTimingEstimate_samples)), ...
    'Different timing fields must retain their own source values, without substitution.');
assert(all(view.ResidualCFO_PostCorrection_Hz==0) && ...
    isequal(view.ResidualCFO_EstimatedPostCorrection_Hz(1:2),[0;7.25]) && ...
    all(isnan(view.ResidualCFO_EstimatedPostCorrection_Hz(3:4))), ...
    'Missing receiver measurements must not be replaced by reference residuals.');
assert(view.ReceiverResidualObservationStatus(1)=="same_observation_consistency_not_independent_accuracy" && ...
    view.ReceiverResidualObservationStatus(2)=="reported_independence_not_established" && ...
    all(view.ReceiverResidualObservationStatus(3:4)=="not_reported_by_receiver"));
assert(~any(view.ReceiverAccuracyQualified) && ...
    all(a.Tables.CFO.CFOReferenceResidualCheckOk) && ...
    ~any(a.Tables.CFO.CFOEstimatorQualificationOk) && ...
    ~any(a.Tables.Timing.TimingReceiverAccuracyQualified), ...
    'Legacy reference checks cannot certify receiver accuracy.');
saved=readtable(a.SynchronizationObservations,'TextType','string','VariableNamingRule','preserve');
assert(height(saved)==4 && ...
    isequaln(saved.ResidualCFO_EstimatedPostCorrection_Hz,view.ResidualCFO_EstimatedPostCorrection_Hz) && ...
    isequal(saved.TimingMetricRole(1:2),observations.TimingMetricRole));
empty=sixgr.analytics.writeRFInterferenceReconciliation(runtime, ...
    fullfile(root,'no_trials'),struct(),struct(),struct());
assert(isempty(empty.Tables.SynchronizationObservations), ...
    'An empty run must not acquire synthetic synchronization observation rows.');
fprintf('RF_SYNC_CONFIGURATION_NUMERICAL_FIXTURES=%s\n',root);
ok=true;
end
