function ok = testSIB1PhysicalElementTDLCausalRecovery()
%TESTSIB1PHYSICALELEMENTTDLCAUSALRECOVERY Non-centred SSB over real 2x2 TDL.

setup6GRSimToolkit("Verbose", false);
root = fileparts(fileparts(mfilename("fullpath")));
runnerSource = fileread(fullfile(root,"+sixgr","+truth","runWaveformLinkBundle.m"));
assert(contains(runnerSource,'"RuntimeSlot", runtimeSlot - 1}'), ...
    "Coupled one-based slots must be converted at the zero-based cell-search boundary.");
scenarioPath = fullfile(root, "simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tempdir, ...
    "sixgr_sib1_physical_element_tdl_causal_recovery"));

out = sixgr.link.runCellSearch_MIB_SIB1(cfg, ...
    "NumSubframes", 5, "UseRuntimeChannel", true, "RuntimeSlot", 0);

assert(logical(out.RuntimeChannelStateUsed), ...
    "The physical-element regression must traverse the runtime TDL channel.");
assert(logical(out.Ok) && logical(out.PBCH.Ok), ...
    "Physical-element TDL initial access must pass PBCH and strict SIB1.");
assert(double(out.Sync.NCellID) == double(cfg.phy.carrier.NCellID), ...
    "Blind PSS/SSS recovery selected the wrong physical cell ID.");
assert(abs(double(out.FreqOffsetEstimate_Hz)) <= 1e-6, ...
    "Point-A SSB placement must not be mislabeled as oscillator CFO.");
assert(logical(out.SIB1.DCICrcPass) && logical(out.SIB1.DLSCHCrcPass), ...
    "MIB-derived Type-0 DCI and SIB1 DL-SCH must pass on the same capture.");
assert(logical(out.SIB1.SIB1TreeEqual), ...
    "Decoded SIB1 ASN.1 semantics must equal the transmitted tree.");
ssbTx = out.SSBTxEvidence;
assert(double(ssbTx.ConfiguredBeamCount) == 4 && ...
    double(ssbTx.ExecutedBeamCount) == 4 && ...
    isequal(double(ssbTx.ActiveSSBIndices0Based(:)).', 0:3), ...
    "The production SSB waveform must execute the configured four-beam burst set.");
assert(logical(ssbTx.BeamformingApplied) && ...
    logical(ssbTx.ExplicitBeamWeightsApplied) && ...
    string(ssbTx.WaveformDomain) == "physical_element_domain" && ...
    double(ssbTx.WaveformPorts) == 2 && ...
    double(ssbTx.PhysicalTransmitAntennaElements) == 2, ...
    "SSB beam weights must be applied to the configured physical antenna domain.");
assert(all(strlength(string(ssbTx.PrecoderIDs)) > 0) && ...
    all(strlength(string(ssbTx.PrecoderMatrixSHA256)) == 64) && ...
    strlength(string(ssbTx.BurstPlanSHA256)) == 64, ...
    "The SSB burst must expose exact beam identifiers and immutable matrix/plan digests.");
assert(isfinite(double(out.PSSMetric)) && double(out.PSSMetric) > 0, ...
    "Production cell search must expose the measured winning PSS correlation metric.");
assert(isfinite(double(out.SSSMetric)) && double(out.SSSMetric) > 0 && ...
    isfinite(double(out.SSSMetricMargin)), ...
    "Production cell search must expose measured SSS correlation and margin.");
assert(all(isfinite(double([out.PSSSearchSamples, ...
    out.PSSTimingLagsEvaluated, out.PSSSequences, ...
    out.PSSCorrelationVectors, out.SSSSequenceHypotheses, ...
    out.PBCHDMRSHypothesesTested]))) && ...
    all(double([out.PSSSearchSamples, out.PSSTimingLagsEvaluated, ...
    out.PSSSequences, out.PSSCorrelationVectors, ...
    out.SSSSequenceHypotheses, out.PBCHDMRSHypothesesTested]) > 0), ...
    "C0-derived search-complexity measurements must be emitted by the canonical receiver path.");

timing = sixgr.phy.frame.SSBTimingResolver.resolveFromConfig(cfg);
grid = timing.GridRelationship;
expectedOffsetHz = 0.5 * (double(grid.SSBLowOffsetFromPointAHz) + ...
    double(grid.SSBHighOffsetFromPointAHz)) - ...
    0.5 * (double(grid.CarrierLowOffsetFromPointAHz) + ...
    double(grid.CarrierHighOffsetFromPointAHz));
assert(abs(double(out.SIB1.SSBCenterFrequencyOffsetHz) - expectedOffsetHz) <= 1e-6, ...
    "Recovered SSB offset must match the YAML-derived canonical Point-A relationship.");
assert(abs(double(out.SIB1.SSBPlacementCorrectionAppliedHz) + expectedOffsetHz) <= 1e-6, ...
    "Receiver placement correction must negate the canonical SSB center offset.");

fprintf(["Physical-element TDL SIB1: cell=%d beam=%d CFO=%.3f Hz " + ...
    "PBCH/DCI/DLSCH/tree=PASS.\n"], double(out.Sync.NCellID), ...
    double(out.SSBIndex), double(out.FreqOffsetEstimate_Hz));
ok = true;
end
