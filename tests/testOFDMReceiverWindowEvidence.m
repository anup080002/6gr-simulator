function ok = testOFDMReceiverWindowEvidence()
% FFT placement, waveform processing, and calibration must use one option.
carrier = nrCarrierConfig("NSizeGrid", 25, "SubcarrierSpacing", 15);
args = {"Windowing", 0, "NumNoiseRE", 65536};
sixgr.phy.waveform.calibrateOFDMNoiseTransform(carrier, args{:}, ...
    "CyclicPrefixFraction", 0.25, "ForceRecompute", true);
cached = sixgr.phy.waveform.calibrateOFDMNoiseTransform(carrier, args{:}, ...
    "CyclicPrefixFraction", 0.75);
fresh = sixgr.phy.waveform.calibrateOFDMNoiseTransform(carrier, args{:}, ...
    "CyclicPrefixFraction", 0.75, "UseCache", false);
assert(isequal(cached.MeasuredGridNoiseVariance, fresh.MeasuredGridNoiseVariance), ...
    "Changing FFT-window placement must not reuse calibration from another position.");
assert(cached.CyclicPrefixFraction == 0.75 && cached.FFTWindowIncludedInCalibrationKey, ...
    "Calibration must disclose the actual receiver FFT-window option.");

t = reshape(1:(300*14), 300, 14);
grid = exp(1i*t/17);
wave = sixgr.phy.waveform.ofdmModulate(carrier, grid, "Windowing", 0);
for fraction = [0.25 0.5 0.75]
    [observed, evidence] = sixgr.phy.waveform.ofdmDemodulate(carrier, wave, ...
        "CyclicPrefixFraction", fraction);
    expected = nrOFDMDemodulate(carrier, wave, "CyclicPrefixFraction", fraction);
    assert(isequal(observed, expected), ...
        "The wrapper must execute the requested FFT window exactly.");
    assert(evidence.CyclicPrefixFraction == fraction && ...
        evidence.NoiseTransform.CyclicPrefixFraction == fraction && ...
        string(evidence.FFTWindowPositionSource) == "explicit_cyclic_prefix_fraction", ...
        "Receiver evidence and noise transform must bind the executed FFT position.");
end
[~, defaultEvidence] = sixgr.phy.waveform.ofdmDemodulate(carrier, wave);
assert(defaultEvidence.CyclicPrefixFraction == 0.5 && ...
    string(defaultEvidence.FFTWindowPositionSource) == "documented_toolbox_default", ...
    "An omitted FFT position must remain distinguishable from an explicit setting.");

% Nondefault sampling must describe the very same transform that executed.
samplingArgs = {"Nfft", 1024, "SampleRate", 15.36e6, ...
    "CarrierFrequency", 2.35e9};
customWave = sixgr.phy.waveform.ofdmModulate(carrier, grid, ...
    samplingArgs{:}, "Windowing", 0);
[customGrid, customEvidence] = sixgr.phy.waveform.ofdmDemodulate( ...
    carrier, customWave, samplingArgs{:}, "CyclicPrefixFraction", 0.75);
expectedGrid = nrOFDMDemodulate(carrier, customWave, ...
    samplingArgs{:}, "CyclicPrefixFraction", 0.75);
expectedInfo = nrOFDMInfo(carrier, samplingArgs{:}, "Windowing", 0);
assert(isequal(customGrid, expectedGrid), ...
    "Explicit sampling and carrier phase compensation must execute exactly.");
for field = ["Nfft", "SampleRate", "CyclicPrefixLengths", "SymbolLengths", "SymbolPhases"]
    assert(isequal(customEvidence.(field), expectedInfo.(field)), ...
        "Receiver %s metadata must describe the executed options, not defaults.", field);
end
assert(customEvidence.Nfft == customEvidence.NoiseTransform.Nfft && ...
    customEvidence.SampleRate == customEvidence.NoiseTransform.SampleRate, ...
    "Receiver and calibrated transform sampling authorities must agree.");
ok = true;
end
