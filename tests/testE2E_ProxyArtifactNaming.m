function ok = testE2E_ProxyArtifactNaming()
%TESTE2E_PROXYARTIFACTNAMING Removed proxy artifact modes must fail closed.

setup6GRSimToolkit("Verbose", false);
cfg = sixgr.config.defaultConfig();
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.run.seed = 19;

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

threw = false;
try
    sixgr_run_3gpp_full_campaign(cfg, ...
        "ResultsRoot", tmp, ...
        "Verbose", false, ...
        "SetupToolboxChecks", false, ...
        "OnlyE2E", true, ...
        "RunE2EStackProbe", true, ...
        "E2EDuration_s", 0.02, ...
        "E2EMaxSlots", 24, ...
        "E2EUECount", 2, ...
        "E2ETrafficModel", "xr", ...
        "E2EAirModel", "lut", ...
        "E2EEnableAI", false, ...
        "E2ESaveFigures", false, ...
        "UseMexAcceleration", true, ...
        "UseParallelAcceleration", false, ...
        "AutoBuildMexAcceleration", false, ...
        "VerifyArtifacts", false, ...
        "GenerateCampaignPlots", false, ...
        "E2EStrictValidation", false); %#ok<NASGU>
catch ME
    threw = strcmp(ME.identifier, "sixgr:campaign:ProxyModeRemoved");
end
assert(threw, "Removed proxy artifact modes must fail closed.");

ok = true;
end
