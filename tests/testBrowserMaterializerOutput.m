function ok = testBrowserMaterializerOutput()
% No scenario or Python process: exercise the production CLI-result parser.
payload = struct('run_folder', 'C:\\runs\\{actual}\\quoted"name', ...
    'created_count', 584, 'tables_missing', 0, 'charts_missing', 3, ...
    'nested', struct('names', {{'P_FA','FAR','false alarm rate'}}));
diagnostic = "Filesystem contract verification incomplete. Missing charts: [P_FA, FAR, false alarm rate]";
raw = "publisher warning" + newline + string(jsonencode(payload)) + newline + diagnostic;
parsed = sixgr.artifact.parseBrowserMaterializerOutput(1, raw);
assert(parsed.Status == 1 && parsed.CreatedCount == 584 && ...
    parsed.MissingTableCount == 0 && parsed.MissingChartCount == 3);
assert(parsed.PayloadText == raw, 'Never discard the original failure details.');
passed = sixgr.artifact.parseBrowserMaterializerOutput(0, ...
    '{"created_count":1,"tables_missing":0,"charts_missing":0}');
assert(passed.Status == 0 && passed.MissingChartCount == 0 && passed.CreatedCount == 1);
for invalid = ["no JSON", '{"tables_missing":0', ...
        '{"tables_missing":null,"charts_missing":null}', ...
        '{"tables_missing":-1,"charts_missing":0.5}', ...
        '{"tables_missing":"0","charts_missing":[0,0]}', ...
        '{"tables_missing":false,"charts_missing":true}']
    got = sixgr.artifact.parseBrowserMaterializerOutput(0, invalid);
    assert(isnan(got.MissingTableCount) && isnan(got.MissingChartCount), ...
        'Malformed coverage must remain unknown, not zero.');
end
% A failed process with complete counts still must not become successful.
got = sixgr.artifact.parseBrowserMaterializerOutput(7, ...
    '{"tables_missing":0,"charts_missing":0}');
assert(got.Status == 7);
source = fileread(which('sixgr.artifact.materializeBrowserContractArtifacts'));
assert(contains(source, 'sixgr.artifact.parseBrowserMaterializerOutput(status, raw)'));
ok = true;
fprintf('BROWSER_MATERIALIZER_OUTPUT_PASS failure_counts_and_diagnostics_preserved=1\n');
end
