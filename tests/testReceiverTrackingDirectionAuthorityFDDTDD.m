function testReceiverTrackingDirectionAuthorityFDDTDD
%TESTRECEIVERTRACKINGDIRECTIONAUTHORITYFDDTDD Receiver sync is endpoint-local.

ctx = struct( ...
    "TRSTimingEstimateAvailable", true, ...
    "TRSTimingEstimate_samples", 43, ...
    "TRSCFOEstimateAvailable", true, ...
    "TRSEstimatedCFO_Hz", 218.25, ...
    "TRSEstimatedOscillatorCFO_Hz", 17.5);

for duplex = ["FDD","TDD"] %#ok<NASGU>
    dl = sixgr.phy.rx.authorizeReceiverTrackingDirection(ctx, "DL", "DL");
    assert(dl.TrackingDirectionCompatible);
    assert(dl.TRSTimingEstimateAvailable && dl.TRSTimingEstimate_samples == 43);
    assert(dl.TRSCFOEstimateAvailable && dl.TRSEstimatedCFO_Hz == 218.25);
    assert(string(dl.TrackingAuthorityStatus) == "authorized_same_receiver_direction");

    ul = sixgr.phy.rx.authorizeReceiverTrackingDirection(ctx, "DL", "UL");
    assert(~ul.TrackingDirectionCompatible);
    assert(~ul.TRSTimingEstimateAvailable && isnan(ul.TRSTimingEstimate_samples));
    assert(~ul.TRSCFOEstimateAvailable && isnan(ul.TRSEstimatedCFO_Hz));
    assert(ul.ObservedTRSTimingEstimateAvailable && ul.ObservedTRSTimingEstimate_samples == 43);
    assert(ul.ObservedTRSCFOEstimateAvailable && ul.ObservedTRSEstimatedCFO_Hz == 218.25);
    assert(string(ul.TrackingAuthorityStatus) == "rejected_cross_direction_receiver_state");

    ulMeasurement = struct( ...
        "TRSTimingEstimateAvailable", true, ...
        "TRSTimingEstimate_samples", 3.5, ...
        "TRSCFOEstimateAvailable", true, ...
        "TRSEstimatedCFO_Hz", -12);
    ulAuthorized = sixgr.phy.rx.authorizeReceiverTrackingDirection( ...
        ulMeasurement, "UL", "UL");
    assert(ulAuthorized.TrackingDirectionCompatible);
    assert(ulAuthorized.TRSTimingEstimateAvailable);
    assert(ulAuthorized.TRSTimingEstimate_samples == 3.5);
end

localAssertThrows(@() sixgr.phy.rx.authorizeReceiverTrackingDirection( ...
    ctx, "SIDEWAYS", "UL"), ...
    "sixgr:phy:rx:InvalidTrackingMeasurementDirection");

% Exercise the production UL receiver boundary.  Even if a caller leaves
% the measured DL values in the struct, the direction tag must prevent the
% PUSCH receiver from shifting an already aligned UL waveform.
if exist("nrPUSCH", "file") == 2 && exist("nrPUSCHDecode", "file") == 2
    cfg = sixgr.config.defaultConfig();
    cfg.channel.model = "AWGN";
    cfg.channel.awgnOnly = true;
    cfg.phy.rx.useIdealTimingSync = false;
    cfg.outputs.saveCSV = false;
    cfg.outputs.saveMAT = false;
    cfg.outputs.saveFigures = false;
    cfg = sixgr.util.structSet(cfg, ...
        "lls6g.receiverSync.RuntimeWaveformSampleAligned", true);
    [tx, ~] = sixgr.phy.ul.PUSCH_Tx(cfg, "CompactOutput", false);
    rejected = sixgr.phy.rx.authorizeReceiverTrackingDirection( ...
        ctx, "DL", "UL");
    rejected.TRSProcessed = true;
    rejected.TrackingEstimateSource = "unit_test_dl_trs_state";
    [rx, info] = sixgr.phy.ul.PUSCH_Rx(tx.Waveform, cfg, ...
        "Carrier", tx.Carrier, ...
        "PUSCH", tx.PUSCH, ...
        "PUSCHIndices", tx.PUSCHIndices, ...
        "TransportBlockSize", tx.TransportBlockSize, ...
        "TargetCodeRate", tx.TargetCodeRate, ...
        "RV", tx.RV, ...
        "CodingLayout", tx.CodingLayout, ...
        "NoiseVar", 1e-6, ...
        "NoiseVarDomain", "time", ...
        "ReceiverTrackingState", rejected, ...
        "SkipTimingEstimate", false);
    assert(~logical(rx.TimingEstimateUsed));
    assert(abs(double(rx.AppliedTimingCorrection_samples)) < 1e-12);
    trackingInfo = info.ReceiverTrackingCorrection;
    assert(string(trackingInfo.AuthorityStatus) == ...
        "rejected_cross_direction_receiver_state", ...
        "Unexpected tracking authority status: %s", ...
        string(trackingInfo.AuthorityStatus));
    assert(string(trackingInfo.MeasurementDirection) == "DL");
    assert(string(trackingInfo.ConsumerDirection) == "UL");
    assert(~logical(trackingInfo.DirectionCompatible));
    % A receiver-local CFO estimate is still allowed after rejecting the
    % opposite-direction state; it must have local UL waveform provenance.
    if logical(trackingInfo.CFOEstimateAvailable)
        assert(any(string(trackingInfo.Source) == [ ...
            "cyclic_prefix_cfo_estimator", ...
            "dmrs_reference_symbol_phase_slope"]));
    end

    % Same-direction RS timing is also observation-only when the runtime
    % channel wrapper has already aligned its output.  This prevents the
    % filter/acquisition delay from being applied twice in either duplex.
    alignedUL = struct( ...
        "TRSProcessed", true, ...
        "TimingEstimateAvailable", true, ...
        "TimingEstimate_samples", 43, ...
        "CFOEstimateAvailable", false, ...
        "TrackingMeasurementDirection", "UL", ...
        "TrackingConsumerDirection", "UL", ...
        "TrackingDirectionCompatible", true, ...
        "TrackingAuthorityStatus", "authorized_same_receiver_direction", ...
        "TrackingEstimateSource", "unit_test_ul_receiver_rs_state");
    [rxAlignedUL, ~] = sixgr.phy.ul.PUSCH_Rx(tx.Waveform, cfg, ...
        "Carrier", tx.Carrier, ...
        "PUSCH", tx.PUSCH, ...
        "PUSCHIndices", tx.PUSCHIndices, ...
        "TransportBlockSize", tx.TransportBlockSize, ...
        "TargetCodeRate", tx.TargetCodeRate, ...
        "RV", tx.RV, ...
        "CodingLayout", tx.CodingLayout, ...
        "NoiseVar", 1e-6, ...
        "NoiseVarDomain", "time", ...
        "ReceiverTrackingState", alignedUL, ...
        "SkipTimingEstimate", false);
    assert(~logical(rxAlignedUL.TimingEstimateUsed));
    assert(abs(double(rxAlignedUL.AppliedTimingCorrection_samples)) < 1e-12);

    [txDL, ~] = sixgr.phy.dl.PDSCH_Tx(cfg, ...
        "ExecutionProfile", "phy_calibration", ...
        "CompactOutput", false);
    alignedDL = alignedUL;
    alignedDL.TrackingMeasurementDirection = "DL";
    alignedDL.TrackingConsumerDirection = "DL";
    alignedDL.TrackingEstimateSource = "unit_test_dl_trs_state";
    [rxAlignedDL, ~] = sixgr.phy.dl.PDSCH_Rx(txDL.Waveform, cfg, ...
        "Carrier", txDL.Carrier, ...
        "PDSCH", txDL.PDSCH, ...
        "PDSCHIndices", txDL.PDSCHIndices, ...
        "TransportBlockSize", txDL.TransportBlockSize, ...
        "TargetCodeRate", txDL.TargetCodeRate, ...
        "RV", txDL.RV, ...
        "CodingPlan", txDL.CodingPlans, ...
        "NoiseVar", 1e-6, ...
        "NoiseVarDomain", "time", ...
        "ExecutionProfile", "phy_calibration", ...
        "ReceiverTrackingState", alignedDL, ...
        "SkipTimingEstimate", false);
    assert(~logical(rxAlignedDL.TimingEstimateUsed));
    assert(abs(double(rxAlignedDL.AppliedTimingCorrection_samples)) < 1e-12);
end

fprintf("testReceiverTrackingDirectionAuthorityFDDTDD: PASS\n");
end

function localAssertThrows(fcn, expectedIdentifier)
threw = false;
try
    fcn();
catch ME
    threw = true;
    assert(strcmp(ME.identifier, expectedIdentifier), ...
        "Expected %s, got %s.", expectedIdentifier, ME.identifier);
end
assert(threw, "Expected %s to be thrown.", expectedIdentifier);
end
