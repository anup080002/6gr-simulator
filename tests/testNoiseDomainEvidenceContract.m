function testNoiseDomainEvidenceContract()
%TESTNOISEDOMAINEVIDENCECONTRACT Guard against mixed sample/grid/EQ planes.

direction = ["DL";"UL"];
sampleN = [0.10;0.20];
gain = [4;5];
gridN = sampleN .* gain;
receiverN = [0.12;0.21];
preEqN = gridN;
postEqN = [0.05;0.06];
llrN = postEqN;
legacy = [postEqN(1);preEqN(2)];
alias = ["PostEqualizationNoiseVariance";"PreEqualizationNoiseVariance"];
signalEnergy = [1;2];
appliedSNR = 10 .* log10(signalEnergy ./ gridN);

T = table(direction, legacy, sampleN, gridN, receiverN, preEqN, postEqN, ...
    llrN, gain, ...
    repmat("receiver_sample_waveform_pre_composite_front_end",2,1), ...
    repmat("resource_grid_pre_equalization",2,1), ...
    repmat("receiver_sample_waveform_post_composite_front_end",2,1), ...
    repmat("resource_grid_pre_equalization",2,1), ...
    repmat("unit_constellation_layer_symbol_post_equalization",2,1), ...
    repmat("unit_constellation_soft_demapper_input",2,1), alias, ...
    repmat("injected_awgn",2,1), repmat("ofdm_transform",2,1), ...
    repmat("post_front_end_measured_variance",2,1), ...
    repmat("dmrs_estimator",2,1), repmat("equalizer",2,1), ...
    repmat("soft_demapper",2,1), ...
    repmat("occupied_resource_grid_re_after_ofdm_demodulation",2,1), ...
    appliedSNR, repmat("occupied_re_energy_over_grid_noise",2,1), ...
    [0.025;0.04], ...
    repmat("receiver_sample_waveform_pre_noise_pre_composite_front_end",2,1), ...
    signalEnergy, true(2,1), [4;7], repmat("OK",2,1), ...
    'VariableNames', { ...
    'Direction','NoiseVariance','ReplaySampleNoiseVariance', ...
    'ReplayGridNoiseVariance','ReceiverInputSampleNoiseVariance', ...
    'PreEqualizationNoiseVariance','PostEqualizationNoiseVariance', ...
    'LLRNoiseVariance','SampleToGridNoiseVarianceGain', ...
    'ReplaySampleNoiseVarianceDomain','ReplayGridNoiseVarianceDomain', ...
    'ReceiverInputSampleNoiseVarianceDomain', ...
    'PreEqualizationNoiseVarianceDomain','PostEqualizationNoiseVarianceDomain', ...
    'LLRNoiseVarianceDomain','NoiseVarianceAliasOf', ...
    'ReplaySampleNoiseVarianceSource','ReplayGridNoiseVarianceSource', ...
    'ReceiverInputSampleNoiseVarianceSource', ...
    'PreEqualizationNoiseVarianceSource','PostEqualizationNoiseVarianceSource', ...
    'LLRNoiseVarianceSource','SNRReferencePlane','AppliedNoiseSNR_dB', ...
    'AppliedNoiseSNRSource','DesiredSignalPowerBeforeNoise', ...
    'DesiredSignalPowerBeforeNoiseDomain','SignalEnergyPerOccupiedRE', ...
    'PostEqSINRAvailable','PostEqSINR_dB','PostEqSINRValueStatus'});

report = sixgr.phy.rx.validateNoiseDomainEvidence(T, "ThrowOnFailure", true);
assert(all(report.Status == "PASS"), "The valid explicit-domain fixture must pass.");

bounded = T;
bounded.PostEqSINRValueStatus = ["OK_DMRS_RESIDUAL_BOUNDED"; ...
    "OK_DECISION_DIRECTED_RESIDUAL_BOUNDED"];
report = sixgr.phy.rx.validateNoiseDomainEvidence(bounded, "ThrowOnFailure", true);
assert(all(report.Status == "PASS"), ...
    "Qualified OK_* receiver-residual bounds must remain available post-equalization SINR evidence.");

bad = T;
bad.ReplayGridNoiseVariance(1) = bad.ReplayGridNoiseVariance(1) .* 2;
localAssertError(@()sixgr.phy.rx.validateNoiseDomainEvidence( ...
    bad, "ThrowOnFailure", true), "sixgr:phy:rx:NoiseDomainEvidenceInvalid");

bad = T;
bad.PostEqSINRAvailable(1) = false;
localAssertError(@()sixgr.phy.rx.validateNoiseDomainEvidence( ...
    bad, "ThrowOnFailure", true), "sixgr:phy:rx:NoiseDomainEvidenceInvalid");

replay = struct( ...
    "InjectedNoiseVariance", 0.25, ...
    "NoiseVarianceSource", "awgn_reference", ...
    "AGCApplied", true, ...
    "AGCGain_dB", 20 .* log10(2), ...
    "ADCQuantizationApplied", true, ...
    "ADCQuantizationErrorVariance", 0.01, ...
    "DesiredSignalPowerBeforeNoise", 0.5, ...
    "CompositeSignalPowerBeforeNoise", 0.75);
out = sixgr.link.applyCompositeFrontEndVarianceReplay(replay);
assert(abs(double(out.InjectedNoiseVariancePreCompositeFrontEnd) - 0.25) < 1e-12);
assert(abs(double(out.InjectedNoiseVariancePostCompositeFrontEnd) - 1.01) < 1e-12);
assert(string(out.InjectedNoiseVarianceAliasOf) == ...
    "InjectedNoiseVariancePostCompositeFrontEnd");
assert(string(out.DesiredSignalPowerBeforeNoiseDomain) == ...
    "receiver_sample_waveform_pre_noise_pre_composite_front_end");
end

function localAssertError(f, expectedId)
thrown = false;
try
    f();
catch ME
    thrown = true;
    assert(string(ME.identifier) == string(expectedId), ...
        "Expected %s but received %s.", expectedId, ME.identifier);
end
assert(thrown, "Expected error %s was not thrown.", expectedId);
end
