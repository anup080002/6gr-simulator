function ok = testPDSCHExactGFromResourcePlan()
%TESTPDSCHEXACTGFROMRESOURCEPLAN Verify rank/codeword G and per-block E.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
map = sixgr.pdsch.PDSCHResourceOwnershipMap( ...
    0:335, struct("RateMatchPattern", 0:47));
dmrs = {48:71};
ptrs = {72:77};
dataRE = 336 - 48 - 24 - 6;

rank4 = localContext(dmrs, ptrs, 4, 6, 3);
plan4 = sixgr.pdsch.PDSCHResourcePlan(map, rank4);
assert(plan4.ExactDataRECount == dataRE && ...
    plan4.GPerCodeword == dataRE * 4 * 6, ...
    "Rank-4 exact G differs from final data RE x layers x Qm.");
assert(sum(plan4.EPerCodeBlock{1}) == plan4.GPerCodeword && ...
    all(mod(plan4.EPerCodeBlock{1}, 4 * 6) == 0), ...
    "Rank-4 per-block E violates its layer/Qm quantum.");

rank8 = localContext(dmrs, ptrs, [4 4], [6 8], [3 4]);
plan8 = sixgr.pdsch.PDSCHResourcePlan(map, rank8);
expectedG = dataRE .* [4 * 6, 4 * 8];
assert(isequal(plan8.GPerCodeword, expectedG), ...
    "Two-codeword rank-8 G was not resolved per codeword.");
for cw = 1:2
    quantum = rank8.LayerCountPerCodeword(cw) * ...
        rank8.QmPerCodeword(cw);
    assert(sum(plan8.EPerCodeBlock{cw}) == expectedG(cw) && ...
        all(mod(plan8.EPerCodeBlock{cw}, quantum) == 0), ...
        "Codeword %d E layout does not exactly sum to G.", cw - 1);
end
assert(plan8.OverlapCounts.DMRSPTRS == 0 && ...
    plan8.OverlapCounts.DMRSReserved == 0 && ...
    plan8.OverlapCounts.PTRSReserved == 0, ...
    "Exact-G plan contains a hidden resource collision.");
ok = true;
end

function context = localContext(dmrs, ptrs, layers, qms, blocks)
context = struct( ...
    "PRBSet", 0:1, "SymbolAllocation", [0 14], ...
    "GridNumPRB", 2, ...
    "GridSymbolsPerSlot",14,"BWPStartPRB",0,"AbsoluteSlot",0, ...
    "UnavailableIndices",zeros(1,0), ...
    "DMRSIndicesPerPort", {dmrs}, ...
    "PTRSIndicesPerPort", {ptrs}, ...
    "DMRSLogicalPortSet",0:(numel(dmrs)-1), ...
    "PTRSLogicalPortSet",0:(numel(ptrs)-1), ...
    "LayerCountPerCodeword", layers, ...
    "QmPerCodeword", qms, ...
    "CodeBlockCountPerCodeword", blocks);
end
