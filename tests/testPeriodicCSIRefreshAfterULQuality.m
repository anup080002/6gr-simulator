function ok = testPeriodicCSIRefreshAfterULQuality()
% Production value-state schema regression for the v141 refresh failure.
% Receiver rows below are declared component inputs, not decoded waveforms.
% Exercise public adaptation, UL enqueue, and periodic CSI producer APIs;
% no actual SRS/CSI/PUSCH reception, control admission, or RF is claimed.
setup6GRSimToolkit('Verbose',false);
scenario = sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_tdd_four_port_received_rank_transition_fixture.yaml');
cfg = sixgr.lls6g.buildInternalConfig(scenario,tempname);
multi = struct('Enabled',true,'NumUsers',1, ...
    'RNTIStart',double(cfg.phy.pusch.RNTI),'ExecutionModel','slot_coupled_truth');
state = sixgr.truth.CoupledTruthRuntime.initialize(cfg,tempname,multi,struct(),50);
initialSchema = string(state.PendingCSITable.Properties.VariableNames);
assert(state.CSIFeedbackSlots == 1 && cfg.phy.pusch.numLayers == 1 && ...
    cfg.phy.pusch.maxLayers == 4 && cfg.phy.pusch.TPMI == 0, ...
    'Retain the actual fixture bootstrap and configured feedback delay.');
assert(cfg.phy.csi.reportPeriodicitySlots == 5 && cfg.phy.csi.reportOffsetSlots == 4 && ...
    cfg.phy.csi.reportConfiguration.NumCSIResources == 1 && ...
    cfg.phy.carrier.SubcarrierSpacing == 15 && ...
    sixgr.truth.periodicCSIReferenceSlot(cfg,10) == 6, ...
    'The rank fixture reports at one-based slot10 using completed reference slot6.');
state.CurrentServingIdx(:) = 1;
% Explicit component precondition, not a fabricated access procedure.
state.ControlGating.PRACHRequired = false;
state.AccessState(:) = "not_required";
state = sixgr.truth.CoupledTruthRuntime.startSlot(state,cfg,'DL',1,1,2,50,40);
assert(isempty(state.PendingCSITable));

% Seed separate spatial clocks via the actual delivered-adaptation owner.
% This is a declared delivery-boundary input, not an accepted SRS capsule.
spatial = struct('CQI',10,'RI',1,'PMI',0,'CRI',NaN,'SINR_dB',NaN, ...
    'SourceSlot',1,'DueSlot',2,'DeliveredSlot',2,'ServingCell',1, ...
    'SourceSignal',"SRS",'ReportIdentity',"declared_spatial_schema_boundary");
[state,spatial] = sixgr.truth.CoupledTruthRuntime.applyDeliveredCSIAdaptationRuntime( ...
    state,spatial,1,'UL',struct());
assert(~spatial.SchedulerSpatialDecisionDeferred && ...
    spatial.SpatialDecisionSourceSlot == 1 && spatial.SpatialDecisionDeliveredSlot == 2);

measurement = table(1,true,true,true,true,true,true,10,1,0,0,0,18.5, ...
    "declared_CSI_refresh_schema_fixture", ...
    'VariableNames',{'Slot','Transmitted','Observed','Consumed', ...
    'ResourceExtractionAvailable','ChannelEstimateAvailable','CSIMeasurementAvailable', ...
    'CQI','RI','PMI','CRI','LI','SINR_dB','MeasurementSource'});
% Four-port Type-I reporting requires the complete declared PMI tuple,
% not the scalar-only two-port fixture. Use the installed codebook owner;
% these remain component inputs, not a received selection or an oracle.
request = cfg.phy.csi.reportConfiguration;
request.Rank = measurement.RI;
[~,tuple] = sixgr.phy.mimo.TypeISinglePanelCodebook.matrix(request,measurement.PMI);
assert(sixgr.phy.mimo.TypeISinglePanelCodebook.linearIndex(request,tuple) == measurement.PMI);
for field = string(fieldnames(tuple)).'
    measurement.(field) = tuple.(field);
end
state = sixgr.truth.CoupledTruthRuntime.applyCSIRSTrial(state,1,measurement);
state = sixgr.truth.CoupledTruthRuntime.startSlot(state,cfg,'DL',1,1,7,50,40);
original = state.PendingCSITable;
assert(height(original) == 1 && original.DueSlot == 10 && ...
    original.CSIReferenceSlot == 6 && original.SourceSlot == 1 && ...
    string(original.SourceSignal) == "CSI-RS");

% The delivered UL report is produced, not manually appended to the table.
% Its quality clock must advance without relabeling the earlier spatial one.
quality = table(5,10,1,0,true, ...
    'VariableNames',{'Slot','WidebandCQI','Layers','PMI','CRCPass'});
quality.ULSpatialMeasurementEvidenceJSON = string(jsonencode(struct( ...
    'ChannelEstimateDomain',"pusch_dmrs_effective_layer_domain", ...
    'RI',1,'RISource',"ul_pusch_dmrs_effective_layer_rank_descriptor_not_srs_ri", ...
    'SRSRITPMIValid',false)));
state = sixgr.truth.CoupledTruthRuntime.enqueueCSIReportRuntime( ...
    state,1,'UL',quality,cfg,table());
ulIndex = find(string(state.PendingCSITable.Direction) == "UL");
assert(isscalar(ulIndex));
delivered = state.PendingCSITable(ulIndex,:);
clockFields = ["SpatialDecisionSourceSlot","SpatialDecisionDeliveredSlot", ...
    "QualityMeasurementSourceSlot","QualityMeasurementDeliveredSlot"];
assert(delivered.Processed && delivered.SourceSlot == 5 && ...
    delivered.DueSlot == 6 && delivered.DeliveredSlot == 7 && ...
    string(delivered.AdaptationDeliveryStatus) == "accepted_new_feedback_delivery" && ...
    ~delivered.SchedulerSpatialDecisionDeferred && ...
    isequal(delivered{1,cellstr(clockFields)},[1 2 5 7]));
assert(isequaln(state.PendingCSITable(1,:),original), ...
    'UL delivery must not populate the earlier pending DL report with UL clocks.');

newer = measurement; newer.Slot = 6; newer.CQI = 11;
ready = sixgr.truth.CoupledTruthRuntime.applyCSIRSTrial(state,1,newer);
beforeUL = ready.ULLinkAdaptationState;
beforeDL = ready.DLLinkAdaptationState;
beforeLatest = ready.LatestULFeedback;
refreshed = sixgr.truth.CoupledTruthRuntime.refreshPeriodicCSIReportsRuntime(ready);
assert(height(refreshed.PendingCSITable) == 2);
assert(isequaln(refreshed.PendingCSITable(ulIndex,:),delivered), ...
    'Refreshing DL CSI must preserve the original delivered UL report exactly.');
pending = refreshed.PendingCSITable(1,:);
assert(string(pending.ReportIdentity) == string(original.ReportIdentity) && ...
    pending.SourceSlot == 6 && pending.DueSlot == 10 && pending.CSIReferenceSlot == 6 && ...
    pending.EnqueuedSlot == 7 && pending.CQI == 11 && isnan(pending.DeliveredSlot));
assert(all(isnan(pending{1,cellstr(clockFields)})) && ...
    ~pending.Processed && ~pending.CSIUCIDecodeOk && isnan(pending.CRCPass) && ...
    string(pending.AdaptationDeliveryStatus) == "not_evaluated", ...
    'Fresh UE payloads have neither delivered spatial/quality authority nor decoded UCI.');
assert(isequaln(refreshed.ULLinkAdaptationState,beforeUL) && ...
    isequaln(refreshed.DLLinkAdaptationState,beforeDL) && ...
    isequaln(refreshed.LatestULFeedback,beforeLatest));
again = sixgr.truth.CoupledTruthRuntime.refreshPeriodicCSIReportsRuntime(refreshed);
assert(isequaln(again.PendingCSITable,refreshed.PendingCSITable));
assert(all(ismember(clockFields,initialSchema)), ...
    'The canonical empty schema must declare adaptation clocks before any delivery.');
assert(isempty(refreshed.PUCCHGrantTraceTable) && ...
    isempty(sixgr.util.structGet(refreshed,'SharedGNBCSIReportTable',table())), ...
    'This value-state producer test cannot claim a waveform grant or received UCI.');

% Preserve strict replacement rejection: do not auto-fill unknown evidence
% columns or copy them from a different report to make the refresh succeed.
bad = ready;
bad.PendingCSITable.UndeclaredReceiverEvidence = ones(height(bad.PendingCSITable),1);
try
    sixgr.truth.CoupledTruthRuntime.refreshPeriodicCSIReportsRuntime(bad);
catch cause
    assert(strcmp(cause.identifier,'sixgr:truth:IncompleteCompatibleTableRow'));
    assert(contains(cause.message,'UndeclaredReceiverEvidence'));
    fprintf(['PERIODIC_CSI_AFTER_UL_QUALITY_PASS spatial=1/2 quality=5/7 ' ...
        'refreshed_source=6 due=10 reference=6 pending_authority=unavailable ' ...
        'unknown_schema_rejected=1 waveform_executions=0\n']);
    ok = true;
    return;
end
error('sixgr:test:MissingCSIRefreshSchemaRejection', ...
    'An undeclared destination evidence column must remain a strict schema error.');
end
