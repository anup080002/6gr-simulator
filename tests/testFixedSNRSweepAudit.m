function ok = testFixedSNRSweepAudit()
%TESTFIXEDSNRSWEEPAUDIT Fixed-SNR sweep audit must pass good evidence and fail bad evidence.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
cleanupObj = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

snrGrid = [18 24 30];
trialsPerPoint = 1;
cfg = localFixtureConfig();
opt = localCampaignOptions(cfg, snrGrid, trialsPerPoint, 271828);

sixgr.truth.runWaveformLinkBundle(cfg, fullfile(tmp, "air_interface"), opt); %#ok<NASGU>
if usejava("jvm")
    sixgr.visual.plotFixedSNRSweepCurves(tmp);
end
localWriteAuditPrereqs(tmp, snrGrid, trialsPerPoint);

audit = sixgr.validation.auditFixedSNRSweepRun(tmp, "Strict", false, "WriteOutputs", true);
if ~logical(audit.Ok)
    disp(audit.Table(string(audit.Table.Status)=="FAIL",:));
    disp(audit.FailureCodes);
end
assert(logical(audit.Ok), "A correct fixed SNR sweep fixture must pass the fixed-sweep audit.");
assert(exist(fullfile(tmp, "reports", "csv", "fixed_snr_sweep_audit.csv"), "file") == 2, ...
    "The fixed-sweep audit CSV must be written.");
assert(exist(fullfile(tmp, "reports", "csv", "fixed_snr_sweep_monotonicity_audit.csv"), "file") == 2, ...
    "The monotonicity audit CSV must be written.");
assert(exist(fullfile(tmp, "reports", "csv", "fixed_snr_sweep_required_outputs.csv"), "file") == 2, ...
    "The required-outputs audit CSV must be written.");
assert(exist(fullfile(tmp, "reports", "json", "fixed_snr_sweep_audit.json"), "file") == 2, ...
    "The fixed-sweep audit JSON must be written.");

crossingPath = fullfile(tmp, "reports", "csv", ...
    "fixed_snr_sweep_curve_crossing.csv");
originalCrossing = readtable(crossingPath, "VariableNamingRule", ...
    "preserve", "TextType", "string");
assert(~isempty(originalCrossing) && ...
    ~any(lower(string(originalCrossing.Status)) == "reported"), ...
    ["A nonempty crossing status must not be generically reported; " ...
     "it must be qualified or explicitly unqualified."]);

% Force a known six-dB bracket around BLER=0.1.  With the configured two-dB
% maximum, the audit must fail even though the crossing row is present.
resolvedPath = fullfile(tmp, "meta", "scenario_config_resolved.json");
originalResolved = sixgr.util.jsonRead(resolvedPath);
resolved = originalResolved;
resolved.validation.fixed_link_campaign.target_bler = 0.1;
resolved.validation.fixed_link_campaign.max_target_crossing_bracket_db = 2;
sixgr.util.jsonWrite(resolvedPath, resolved);
dlCurvePath = fullfile(tmp, "reports", "csv", "dl_fixed_snr_bler_curve.csv");
ulCurvePath = fullfile(tmp, "reports", "csv", "ul_fixed_snr_bler_curve.csv");
originalDL = readtable(dlCurvePath, "VariableNamingRule", "preserve", "TextType", "string");
originalUL = readtable(ulCurvePath, "VariableNamingRule", "preserve", "TextType", "string");
forcedDL = localForceUnderresolvedCurve(originalDL);
forcedUL = localForceUnderresolvedCurve(originalUL);
sixgr.analytics.writeAnalysisTable(dlCurvePath, forcedDL);
sixgr.analytics.writeAnalysisTable(ulCurvePath, forcedUL);
crossingT = table(["DL";"UL"], repmat("AWGN", 2, 1), ...
    [double(forcedDL.MCS(1)); double(forcedUL.MCS(1))], [0.1;0.1], ...
    [NaN;NaN], repmat("crossing_underresolved_bracket", 2, 1), ...
    repmat("unqualified", 2, 1), ...
    repmat("crossing_underresolved_bracket", 2, 1), ...
    'VariableNames', {'Direction','ChannelModel','MCS','TargetBLER', ...
    'TargetCrossingSNR_dB','TargetCrossingStatus','Status','FailureCode'});
sixgr.analytics.writeAnalysisTable(crossingPath, crossingT);
auditUnderresolved = sixgr.validation.auditFixedSNRSweepRun(tmp, ...
    "Strict", false, "WriteOutputs", false);
assert(~logical(auditUnderresolved.Ok) && any(string( ...
    auditUnderresolved.FailureCodes) == "crossing_underresolved_bracket"), ...
    "An observed target crossing wider than the YAML bracket must fail closed.");
sixgr.util.jsonWrite(resolvedPath, originalResolved);
sixgr.analytics.writeAnalysisTable(dlCurvePath, originalDL);
sixgr.analytics.writeAnalysisTable(ulCurvePath, originalUL);
sixgr.analytics.writeAnalysisTable(crossingPath, originalCrossing);

runClassPath = fullfile(tmp, "reports", "csv", "run_classification.csv");
runClassT = readtable(runClassPath, "VariableNamingRule", "preserve", "TextType", "string");
runClassT.RunClass(:) = "geometry_network_lls";
sixgr.util.csvWriteTable(runClassPath, runClassT);
auditClassMismatch = sixgr.validation.auditFixedSNRSweepRun(tmp, ...
    "Strict", false, "WriteOutputs", false);
assert(~logical(auditClassMismatch.Ok), ...
    "A runtime run class that conflicts with the resolved YAML must fail the audit.");
assert(any(string(auditClassMismatch.FailureCodes) == "run_class_config_runtime_mismatch"), ...
    "The audit must report the exact resolved-config/runtime run-class mismatch.");
runClassT.RunClass(:) = "fixed_snr_sweep_lls";
sixgr.util.csvWriteTable(runClassPath, runClassT);

ulCurvePath = fullfile(tmp, "reports", "csv", "ul_fixed_snr_bler_curve.csv");
ulCurve = readtable(ulCurvePath, "VariableNamingRule", "preserve", "TextType", "string");
sixgr.util.csvWriteTable(ulCurvePath, ulCurve([],:));
auditMissingUL = sixgr.validation.auditFixedSNRSweepRun(tmp, "Strict", false, "WriteOutputs", false);
assert(~logical(auditMissingUL.Ok), "An empty UL BLER curve must fail the fixed-sweep audit.");
assert(any(contains(string(auditMissingUL.FailureCodes), "ul_curve_missing_or_empty")) || ...
    any(contains(string(auditMissingUL.FailureCodes), "required_output_missing_or_empty")), ...
    "The fixed-sweep audit must explain that the UL curve is missing or empty.");

sixgr.util.csvWriteTable(ulCurvePath, ulCurve);
dlCurvePath = fullfile(tmp, "reports", "csv", "dl_fixed_snr_bler_curve.csv");
dlCurve = readtable(dlCurvePath, "VariableNamingRule", "preserve", "TextType", "string");
dlCurve.BLER(1) = 1.2;
dlCurve.BLER_CI_Low(1) = 1.1;
dlCurve.BLER_CI_High(1) = 1.3;
dlCurve.BLER_CI_Width(1) = 0.2;
sixgr.util.csvWriteTable(dlCurvePath, dlCurve);
auditInvalidBLER = sixgr.validation.auditFixedSNRSweepRun(tmp, "Strict", false, "WriteOutputs", false);
assert(~logical(auditInvalidBLER.Ok), "BLER values above 1 must fail the fixed-sweep audit.");
assert(any(contains(string(auditInvalidBLER.FailureCodes), "bler_out_of_range")) || ...
    any(contains(string(auditInvalidBLER.FailureCodes), "bler_ci_invalid")), ...
    "The fixed-sweep audit must flag invalid BLER evidence.");

ok = true;
end

function T = localForceUnderresolvedCurve(T)
assert(height(T) == 3, "The fixed-sweep audit fixture must retain three SNR rows.");
T.BLER = [1; 0.5; 0];
T.BLER_CI_Low = T.BLER;
T.BLER_CI_High = T.BLER;
T.BLER_CI_Width = zeros(3, 1);
T.Incomplete = false(3, 1);
end

function cfg = localFixtureConfig()
scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "master_sinr_sweep.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tempdir, "fixed_snr_sweep_audit_fixture"));
cfg.run.numFrames = 1;
cfg.run.strictMode = false;
cfg.run.noProxyTruthContract = false;
cfg.run.interferenceExecutionMode = "none";
cfg.run.fixedReferenceMode = true;
cfg.run.noiseOperatingMode = "standalone_awgn_snr_argument";
cfg.run.seed = 4207;
% This is a focused three-point audit fixture, not a parallel-execution
% qualification.  Keep it serial so the validator cannot spend minutes
% starting process workers or inherit the master campaign's worker policy.
cfg.run.numWorkers = 1;
cfg.run.parallelRequestedWorkers = 1;
cfg.run.useParallel = false;
cfg.run.autoStartParallelPool = false;
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.fading.enable = false;
cfg.channel.snr_dB = 18;
cfg.run.runTag = "fixed_snr_sweep_audit_fixture";
cfg.run.executionID = "fixed_snr_sweep_audit_fixture_execution";
cfg.run.scenarioID = "fixed_snr_sweep_audit_fixture";
cfg.meta.executionID = cfg.run.executionID;
cfg.meta.configHash = "";
cfg.meta.configHash = string(sixgr.util.sha256Hex(uint8( ...
    unicode2native(jsonencode(cfg), "UTF-8"))));
end

function opt = localCampaignOptions(cfg, snrGrid, trialsPerPoint, seed)
campaignCfg = struct( ...
    "Enabled", true, ...
    "SNR_dB", double(snrGrid(:)).', ...
    "MinTBPerPoint", double(trialsPerPoint), ...
    "MaxTBPerPoint", double(trialsPerPoint), ...
    "MinErrorsForCI", 0, ...
    "MaxCIHalfWidth", 1, ...
    "BatchTBCount", 1, ...
    "TargetBLER", 0.1, ...
    "ConfidenceLevel", 0.95, ...
    "SeedBase", double(seed), ...
    "Seeds", double(seed), ...
    "ParallelWorkers", 0);
opt = struct( ...
    "LinkDuration_s", 0.001, ...
    "LinkMaxSimFrames", 1, ...
    "FixedLinkCampaignOnly", true, ...
    "LinkSNR_dB", double(cfg.channel.snr_dB), ...
    "LinkSNRGrid_dB", double(cfg.channel.snr_dB), ...
    "LinkSweepFrames", 1, ...
    "LinkSweepTrialsPerSNR", 1, ...
    "LinkSweepMaxPoints", 1, ...
    "LinkReferenceSweepFrames", trialsPerPoint, ...
    "LinkAdaptiveSweepEnabled", false, ...
    "LinkFixedLinkCampaignEnabled", true, ...
    "LinkFixedLinkCampaignConfig", campaignCfg, ...
    "LinkFixedLinkSNRGrid_dB", snrGrid, ...
    "LinkFixedLinkMinTrials", trialsPerPoint, ...
    "LinkFixedLinkMaxTrials", trialsPerPoint, ...
    "LinkFixedLinkTrialsPerDrop", 1, ...
    "LinkFixedLinkErrorTarget", 0, ...
    "LinkFixedLinkCIWidthTarget", 1, ...
    "LinkFixedLinkConfidenceLevel", 0.95, ...
    "LinkFixedLinkSeed", seed, ...
    "HARQDiagnosticsEnabled", false, ...
    "LinkAnchorCases", ["DL_PDSCH_Throughput","UL_PUSCH_Throughput"], ...
    "SaveFigures", false);
end

function localWriteAuditPrereqs(runFolder, snrGrid, trialsPerPoint)
layout = sixgr.report.resultLayout(runFolder);
sixgr.util.ensureFolder(layout.MetaDir);
sixgr.util.ensureFolder(layout.ReportCSVDir);

resolved = struct();
resolved.validation = struct( ...
    "run_class", "fixed_snr_sweep_lls", ...
    "fixed_snr_sweep_required", true);
resolved.sweeps_and_matrix = struct( ...
    "fixed_link_calibration", struct( ...
        "enabled", true, ...
        "only", true, ...
        "direction", "both", ...
        "snr_db", double(snrGrid(:)).', ...
        "min_trials", double(trialsPerPoint), ...
        "max_trials", double(trialsPerPoint), ...
        "ci_width_target", 10.0, ...
        "confidence_level", 0.95, ...
        "max_sinr_snr_delta_db", 10.0, ...
        "target_bler", NaN));
resolved.simulation = struct("noise_operating_mode", "standalone_awgn_snr_argument");
sixgr.util.jsonWrite(fullfile(layout.MetaDir, "scenario_config_resolved.json"), resolved);

runClassT = table( ...
    "fixed_snr_sweep_lls", true, true, true, false, ...
    "20", "256QAM", 1, 1, 1.0, false, ...
    "fixed_snr_sweep_lls uses dedicated fixed-sweep audit gating.", ...
    'VariableNames', {'RunClass','FixedMCSActive','RankFixed','ModulationFixed','AdaptiveMode', ...
    'ConfiguredMCS','ConfiguredModulation','ConfiguredRank','ConfiguredLayers', ...
    'ExactConfiguredEffectiveMatchRate','PublicationLLSEligible','Reason'});
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, "run_classification.csv"), runClassT);

% The production raster authority is the CSV-driven Python renderer.  The
% fixed-sweep audit only needs a nonempty canonical lineage at this focused
% unit boundary; raster bytes and hashes are exercised by the Python
% contract/materialization tests.
lineageT = table( ...
    "fixture_fixed_snr_curve", ...
    "reports/csv/dl_fixed_snr_bler_curve.csv", ...
    "reports/image/dl_bler_vs_snr.png", ...
    repmat("a", 1, 64), repmat("b", 1, 64), "pass", ...
    'VariableNames', {'PlotId','SourceCSVPath','ImagePath', ...
    'SourceCSV_SHA256','ImageSHA256','Status'});
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, ...
    "contract_plot_lineage.csv"), lineageT);
end
