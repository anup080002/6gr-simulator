function [ok, report] = testPDSCHArtifactGeneration(varargin)
%TESTPDSCHARTIFACTGENERATION Export and verify real PDSCH phase evidence.
%
% TESTPDSCHARTIFACTGENERATION() builds the production evidence needed by the
% artifact publisher, exports it through the shared production path, and
% runs the Python artifact verifier.  It never calls the phase runner.
%
% TESTPDSCHARTIFACTGENERATION(STAGEDIR, VECTORROOT) validates an already
% exported runner stage.  The phase runner uses this form and records the
% returned observed checks, counts, and duration before publishing.

if nargin ~= 0
    if nargin ~= 2
        error("sixgr:test:PDSCHArtifactGeneration:BadInvocation", ...
            "Validation mode requires exactly stageDir and vectorRoot.");
    end
    [ok, report] = localValidateStage(varargin{1}, varargin{2});
    localRequirePassing(report);
    return;
end

setup6GRSimToolkit("Verbose", false);
testRoot = fileparts(mfilename("fullpath"));
vectorRoot = fullfile(testRoot, "vectors", "pdsch");
stageDir = tempname;
cleanup = onCleanup(@() localRemove(stageDir));
requiredSuites = string(sixgr.pdsch. ...
    PDSCHPhaseFocusedTestExecutor.requiredSuiteNames());
promptMandatorySuites = string(sixgr.pdsch. ...
    PDSCHPhaseArtifactPublisher.promptMandatoryTestSuiteNames());
repositoryRegression = "testPDSCHStudyImmutableCodingPlans";
assert(numel(promptMandatorySuites) == 48 ...
        && numel(unique(promptMandatorySuites)) == 48 ...
        && all(ismember(promptMandatorySuites, requiredSuites)) ...
        && ~ismember(repositoryRegression, promptMandatorySuites) ...
        && nnz(requiredSuites == repositoryRegression) == 1, ...
    ["The publisher must retain exactly 48 Prompt-02 mandatory suites " ...
     "while executing immutable-plan coverage as a repository regression."]);
directSuiteCount = nnz( ...
    requiredSuites ~= "testPDSCHArtifactGeneration");

[vectorExecution, vectorOutput] = localVerifyVectorPack(vectorRoot);
if vectorExecution.Status ~= "PASS"
    error("sixgr:test:PDSCHArtifactGeneration:VectorVerificationFailed", ...
        "PDSCH vector verification failed: %s", vectorOutput);
end
builderStarted = tic;
builder = sixgr.pdsch.PDSCHPhaseEvidenceBuilder.build(vectorRoot);
builderDuration = toc(builderStarted);
builderExecution = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
    executionRow( ...
    "phase_evidence_builder", ...
    "sixgr.pdsch.PDSCHPhaseEvidenceBuilder.build", ...
    "production_evidence_builder", ...
    localStructStatuses(builder), builderDuration, ...
    "tables=" + string(numel(fieldnames(builder))));

coverageStarted = tic;
coverage = sixgr.pdsch.PDSCHCoverageExecutor.run( ...
    "VectorRoot", vectorRoot, ...
    "SeedList", [11 23 47 89], ...
    "ConfidenceLevel", 0.95, ...
    "Strict", true);
coverageDuration = toc(coverageStarted);
coverageExecution = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
    executionRow( ...
    "coverage_executor", ...
    "sixgr.pdsch.PDSCHCoverageExecutor.run", ...
    "production_coverage_executor", ...
    localStructStatuses(coverage), coverageDuration, ...
    "declared=" + string(height(coverage.DeclaredCoverageResults)) ...
    + " pairwise=" + string(height(coverage.PairwiseCases)) ...
    + " no_noise=" + string(height(coverage.NoNoiseRoundTrip)) ...
    + " bler=" + string(height(coverage.BLERCurve)));

[focusedSummary, focusedExecution] = sixgr.pdsch. ...
    PDSCHPhaseFocusedTestExecutor.run(vectorRoot);
assert(height(focusedSummary) == directSuiteCount ...
    && ~any(focusedSummary.TestSuite ...
    == "testPDSCHArtifactGeneration"), ...
    "Standalone preparation must execute every nonrecursive suite.");
assembly = sixgr.pdsch.PDSCHPhaseArtifactPublisher.prepare( ...
    builder, coverage, focusedSummary, ...
    [vectorExecution; builderExecution; coverageExecution; focusedExecution], ...
    stageDir, vectorRoot);
assert(assembly.Passed, ...
    "Production artifact preparation did not pass.");
assert(nnz(assembly.ArtifactInventory.Kind == "CSV") == 19 ...
    && nnz(assembly.ArtifactInventory.Kind == "PNG") == 11, ...
    "Production preparation must emit exactly 19 MATLAB CSVs and 11 PNGs.");

[~, initialValidation] = localValidateStage(stageDir, vectorRoot);
localRequirePassing(initialValidation);
finalized = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
    recordValidation(assembly, initialValidation);

[ok, report] = localValidateStage(stageDir, vectorRoot);
localRequirePassing(report);
inventory = sixgr.pdsch.PDSCHPhaseArtifactPublisher.inventory(stageDir);
sixgr.pdsch.PDSCHPhaseArtifactPublisher.validateInventory( ...
    inventory, 20, 11, "standalone artifact-test output");

artifactRow = finalized.TestSummary( ...
    finalized.TestSummary.TestSuite ...
    == "testPDSCHArtifactGeneration", :);
assert(height(artifactRow) == 1 ...
    && artifactRow.Total == initialValidation.CheckCount ...
    && artifactRow.Passed == initialValidation.PassedCheckCount ...
    && artifactRow.Failed == initialValidation.FailedCheckCount ...
    && artifactRow.Status == "PASS", ...
    "Artifact test summary does not contain the observed validator result.");
assert(height(finalized.TestSummary) == numel(requiredSuites), ...
    "Final PDSCH test summary must contain every direct suite plus the real artifact-stage test.");
executionRow = finalized.PhaseExecutionSummary( ...
    finalized.PhaseExecutionSummary.Source ...
    == "testPDSCHArtifactGeneration", :);
assert(height(executionRow) == 1 ...
    && executionRow.RecordCount == initialValidation.CheckCount ...
    && executionRow.PassedCount == initialValidation.PassedCheckCount ...
    && executionRow.FailedCount == initialValidation.FailedCheckCount ...
    && executionRow.DurationSeconds ...
    == initialValidation.DurationSeconds ...
    && executionRow.Status == "PASS", ...
    "Phase execution summary does not contain the measured artifact test.");

fprintf([ ...
    'PDSCH artifacts: %d CSVs, %d PNGs, %d/%d final checks pass, ' ...
    'verifier exit %d.\n'], ...
    report.CSVCount, report.PNGCount, report.PassedCheckCount, ...
    report.CheckCount, report.VerifierExitCode);
clear cleanup
localRemove(stageDir);
end

function [execution, output] = localVerifyVectorPack(vectorRoot)
script = fullfile(vectorRoot, "verify_pdsch_vector_pack.py");
manifestPath = fullfile(vectorRoot, "independent_vector_manifest.json");
if ~isfile(script) || ~isfile(manifestPath)
    error("sixgr:test:PDSCHArtifactGeneration:VectorVerifierMissing", ...
        "Vector verifier and manifest are required.");
end
if contains(string(script), '"')
    error("sixgr:test:PDSCHArtifactGeneration:UnsafeVectorPath", ...
        "Vector verifier path contains an unsupported quote.");
end
manifest = jsondecode(fileread(manifestPath));
if ~isfield(manifest, "files") || isempty(manifest.files)
    error("sixgr:test:PDSCHArtifactGeneration:BadVectorManifest", ...
        "Vector manifest does not contain authenticated files.");
end
command = sprintf('python "%s"', script);
started = tic;
[status, output] = system(command);
duration = toc(started);
execution = sixgr.pdsch.PDSCHPhaseArtifactPublisher.executionRow( ...
    "vector_pack_verification", "verify_pdsch_vector_pack.py", ...
    "python_preflight", repmat(status == 0, numel(manifest.files), 1), ...
    duration, "files=" + string(numel(manifest.files)) ...
    + " exit=" + string(status));
end

function [ok, report] = localValidateStage(stageDir, vectorRoot)
stageDir = char(string(stageDir));
vectorRoot = char(string(vectorRoot));
if ~isfolder(stageDir)
    error("sixgr:test:PDSCHArtifactGeneration:StageMissing", ...
        "Artifact stage does not exist: %s", stageDir);
end
verifier = fullfile(vectorRoot, "verify_pdsch_artifacts.py");
if ~isfile(verifier)
    error("sixgr:test:PDSCHArtifactGeneration:VerifierMissing", ...
        "Artifact verifier does not exist: %s", verifier);
end
if contains(string(verifier), '"') ...
        || contains(string(stageDir), '"') ...
        || contains(string(vectorRoot), '"')
    error("sixgr:test:PDSCHArtifactGeneration:UnsafePath", ...
        "Artifact validation paths contain an unsupported quote.");
end

command = sprintf('python "%s" "%s" --vector-root "%s"', ...
    verifier, stageDir, vectorRoot);
started = tic;
[verifierExitCode, verifierOutput] = system(command);
durationSeconds = toc(started);

inventory = sixgr.pdsch.PDSCHPhaseArtifactPublisher.inventory(stageDir);
csvCount = nnz(inventory.Kind == "CSV");
pngCount = nnz(inventory.Kind == "PNG");
testSummaryPath = fullfile(stageDir, "pdsch_test_summary.csv");
if isfile(testSummaryPath)
    stagedSummary = localReadStrings(testSummaryPath);
    suiteCount = height(stagedSummary);
    requiredSuites = string(sixgr.pdsch. ...
        PDSCHPhaseFocusedTestExecutor.requiredSuiteNames());
    finalSuiteCount = numel(requiredSuites);
    directSuiteCount = nnz( ...
        requiredSuites ~= "testPDSCHArtifactGeneration");
    hasArtifactSuite = ismember("TestSuite", ...
        string(stagedSummary.Properties.VariableNames)) ...
        && nnz(stagedSummary.TestSuite ...
        == "testPDSCHArtifactGeneration") == 1;
    suiteContractPass = ...
        (~hasArtifactSuite && suiteCount == directSuiteCount) ...
        || (hasArtifactSuite && suiteCount == finalSuiteCount);
else
    stagedSummary = table();
    suiteCount = 0;
    suiteContractPass = false;
end
auditPath = fullfile(stageDir, "pdsch_artifact_verification.csv");
if isfile(auditPath)
    audit = localReadStrings(auditPath);
    if ismember("Status", string(audit.Properties.VariableNames)) ...
            && ~isempty(audit)
        auditStatuses = upper(strtrim(string(audit.Status)));
    else
        auditStatuses = "FAIL";
    end
else
    audit = table();
    auditStatuses = "FAIL";
end
contractStatuses = [ ...
    string(localTernary(verifierExitCode == 0, "PASS", "FAIL")); ...
    string(localTernary(csvCount == 20, "PASS", "FAIL")); ...
    string(localTernary(pngCount == 11, "PASS", "FAIL")); ...
    string(localTernary(suiteContractPass, "PASS", "FAIL"))];
checkStatuses = [auditStatuses(:); inventory.Status(:); contractStatuses];
passedCheckCount = nnz(checkStatuses == "PASS");
failedCheckCount = nnz(checkStatuses == "FAIL");
passed = verifierExitCode == 0 ...
    && csvCount == 20 && pngCount == 11 ...
    && suiteContractPass ...
    && ~isempty(checkStatuses) && failedCheckCount == 0;
errorIdentifier = "";
errorMessage = "";
if ~passed
    errorIdentifier = ...
        "sixgr:test:PDSCHArtifactGeneration:VerificationFailed";
    errorMessage = "verifier_exit=" + string(verifierExitCode) ...
        + " csv=" + string(csvCount) ...
        + " png=" + string(pngCount) ...
        + " suites=" + string(suiteCount) ...
        + " failed_checks=" + string(failedCheckCount) ...
        + " output=" + string(strtrim(verifierOutput));
end
report = struct( ...
    "Passed", logical(passed), ...
    "Status", string(localTernary(passed, "PASS", "FAIL")), ...
    "CheckStatuses", checkStatuses, ...
    "CheckCount", double(numel(checkStatuses)), ...
    "PassedCheckCount", double(passedCheckCount), ...
    "FailedCheckCount", double(failedCheckCount), ...
    "DurationSeconds", double(durationSeconds), ...
    "VerifierExitCode", double(verifierExitCode), ...
    "VerifierCommand", string(command), ...
    "VerifierOutput", string(strtrim(verifierOutput)), ...
    "CSVCount", double(csvCount), ...
    "PNGCount", double(pngCount), ...
    "SuiteCount", double(suiteCount), ...
    "StagedTestSummary", stagedSummary, ...
    "Inventory", inventory, ...
    "VerificationAudit", audit, ...
    "ErrorIdentifier", string(errorIdentifier), ...
    "ErrorMessage", string(errorMessage));
ok = logical(report.Passed);
end

function localRequirePassing(report)
if logical(report.Passed)
    return;
end
error(char(report.ErrorIdentifier), "%s", char(report.ErrorMessage));
end

function statuses = localStructStatuses(value)
statuses = strings(0, 1);
names = string(fieldnames(value));
for name = names.'
    item = value.(name);
    if istable(item) && ~isempty(item) ...
            && ismember("Status", string(item.Properties.VariableNames))
        statuses = [statuses; upper(strtrim(string(item.Status)))]; %#ok<AGROW>
    end
end
if isempty(statuses)
    error("sixgr:test:PDSCHArtifactGeneration:NoObservedStatuses", ...
        "Production evidence does not contain observed status rows.");
end
end

function value = localReadStrings(path)
options = detectImportOptions(path, ...
    "Delimiter", ",", "TextType", "string", ...
    "VariableNamingRule", "preserve");
options = setvartype(options, options.VariableNames, "string");
value = readtable(path, options);
for i = 1:width(value)
    name = value.Properties.VariableNames{i};
    column = string(value.(name));
    column(ismissing(column)) = "";
    value.(name) = column;
end
end

function localRemove(path)
if isfolder(path)
    rmdir(path, "s");
end
end

function value = localTernary(condition, whenTrue, whenFalse)
if logical(condition)
    value = whenTrue;
else
    value = whenFalse;
end
end
