function ok = testE2E_DeadlineMissAccounting()
%TESTE2E_DEADLINEMISSACCOUNTING Ensure deadline misses use latency vs PDB.

setup6GRSimToolkit("Verbose", false);
cfg = sixgr.config.defaultConfig();
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.run.seed = 23;
cfg.traffic.packetDelayBudget_ms = 0.1;
cfg.traffic.rlcSduChunk_bytes = 512;

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmp, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", 0.03, ...
    "E2EMaxSlots", 32, ...
    "E2EUECount", 3, ...
    "E2ETrafficModel", "xr", ...
    "E2EAirModel", "truth", ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", false, ...
    "GenerateCampaignPlots", false, ...
    "E2EStrictValidation", false);

P = rep.E2E.PacketIntegrityTable;
assert(all(logical(P.AccountingIntegrityPass)), ...
    "Deadline misses should not count as packet-accounting bugs when bookkeeping is honest.");
for i = 1:height(P)
    gen = double(P.GeneratedPackets(i));
    miss = double(P.DeadlineMissPackets(i));
    missRate = double(P.DeadlineMissRate(i));
    pdb_ms = double(P.PacketDelayBudget_ms(i));
    if gen <= 0
        continue;
    end
    assert(miss == gen, "Sub-slot packet budget should mark every generated packet as a deadline miss.");
    assert(abs(missRate - 1.0) <= 1e-12, "Deadline miss rate must be miss/generated.");
    if isfinite(double(P.MeanLatency_ms(i)))
        assert(double(P.MeanLatency_ms(i)) > pdb_ms, ...
            "Mean latency should exceed the sub-slot packet-delay budget in this regression.");
    end
end
assert(~logical(rep.E2E.SummaryTable.QoSPass(1)), ...
    "Sub-slot packet budgets should fail QoS even when packet accounting remains correct.");

ok = true;
end
