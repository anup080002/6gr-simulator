function ok = testTDDCausalFourStepRARuntimeTiming()
%TESTTDDCAUSALFOURSTEPRARUNTIMETIMING Guard the shared RA timing boundary.
%
% The test uses the production TDD causal-wiring YAML, a concrete CDL-A
% runtime channel, physical antenna expansion, thermal receiver noise, and
% the real Msg1/Msg2/Msg3/Msg4/RRCSetupComplete waveform chain.  It proves
% that decoded Msg1 timing advance establishes Msg3 timing and that the
% PUSCH receiver does not apply a second DM-RS timing shift.

scenarioPath = fullfile("simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring_tdd.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
runRoot = tempname;
mkdir(runRoot);
cleanup = onCleanup(@() localCleanup(runRoot)); %#ok<NASGU>
cfg = sixgr.config.normalizeConfig( ...
    sixgr.lls6g.buildInternalConfig(scfg, runRoot));

assert(strcmpi(string(sixgr.util.structGet(cfg, "phy.duplex.mode", "")), "TDD"), ...
    "The timing regression must exercise the YAML-selected TDD profile.");
assert(strcmpi(string(sixgr.util.structGet(cfg, "channel.model", "")), "CDL") && ...
        strcmpi(string(sixgr.util.structGet(cfg, "channel.cdlProfile", "")), "CDL-A") && ...
        strcmpi(string(sixgr.util.structGet(cfg, "channel.fading.profile", "")), "CDL-A"), ...
    "The timing regression must use the concrete configured CDL-A channel.");

multiUser = struct("Enabled", true, "NumUsers", 1, "RNTIStart", 1, ...
    "ExecutionModel", "slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfg, runRoot, multiUser, struct(), 1);
state.CurrentSlot = 2;
state.CurrentServingIdx(:) = 1;
[cfgRuntime, ~] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
    cfg, state, 1, "UL");

% Reuse a previously materialized downlink channel, as the real SSB->RA
% transition does. Both direction views refer to one physical fading clock.
[state, dlState] = sixgr.truth.CoupledTruthRuntime.acquireRuntimeChannelStateForControl( ...
    state, cfgRuntime, 1, "DL");
[carrier, ~] = sixgr.phy.grid.makeCarrier(cfgRuntime);
txInfo = struct("OFDM", nrOFDMInfo(carrier));
nBS = double(cfgRuntime.lls6g.userContext.RuntimeServingBSAntennaMeta.NumElements);
nUE = double(cfgRuntime.lls6g.userContext.RuntimeUEAntennaMeta.NumElements);
dlState = sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    dlState, cfgRuntime, complex(zeros(128, nBS)), txInfo, ...
    "NumTxAnt", nBS, "NumRxAnt", nUE, ...
    "TransmitAntennaRuntime", cfgRuntime.lls6g.userContext.RuntimeServingBSAntenna, ...
    "ReceiveAntennaRuntime", cfgRuntime.lls6g.userContext.RuntimeUEAntenna, ...
    "TransmitAntennaMeta", cfgRuntime.lls6g.userContext.RuntimeServingBSAntennaMeta, ...
    "ReceiveAntennaMeta", cfgRuntime.lls6g.userContext.RuntimeUEAntennaMeta);
state = sixgr.truth.CoupledTruthRuntime.commitRuntimeChannelState(state, dlState);
[~, ulState] = sixgr.truth.CoupledTruthRuntime.acquireRuntimeChannelStateForControl( ...
    state, cfgRuntime, 1, "UL");

result = sixgr.phy.ra.runFourStepRA(cfgRuntime, ...
    "RunFolder", runRoot, "RunId", "tdd_causal_ra_timing", ...
    "ScenarioName", "tdd_causal_ra_timing", ...
    "UEId", 1, "CellId", 1, "AttemptId", 1, ...
    "RuntimeIntegrationMode", "coupled_truth_runtime", ...
    "UseRuntimeChannel", true, "RuntimeNoiseSNR_dB", 12, ...
    "InitialDLChannelState", dlState, "InitialULChannelState", ulState, ...
    "RuntimeSlot", 2, "WriteArtifacts", false);

assert(logical(result.RACompleted) && logical(result.StrictOk), ...
    "The TDD measured four-step RA waveform chain must complete strictly.");
assert(logical(result.Msg3PUSCHCrcPass), ...
    "Msg3 PUSCH must decode through the production CDL-A receiver chain.");
assert(logical(result.Msg3TimingAdvanceApplied), ...
    "Msg3 must consume the timing advance decoded from Msg1/RAR state.");
assert(~logical(result.Msg3TimingEstimateUsed), ...
    "An already TA-aligned Msg3 waveform must not perform duplicate DM-RS timing acquisition.");
assert(abs(double(result.Msg3AppliedTimingCorrection_samples)) < 1e-12, ...
    "An already TA-aligned Msg3 waveform must receive zero duplicate timing correction.");
assert(string(result.Msg3TimingEstimateSource) == ...
        "runtime_aligned_waveform_no_timing_reacquisition", ...
    "Msg3 timing provenance must identify the established runtime alignment boundary.");
assert(logical(result.Msg3ChannelEstimateAvailable) && ...
        logical(result.Msg3EqualizationAvailable) && ...
        logical(result.Msg3LLRFinite), ...
    "Msg3 must retain measured channel-estimation, equalization, and finite-LLR evidence.");
assert(~logical(result.ProxyUsed) && ~logical(result.Skipped), ...
    "The TDD RA timing regression must not use proxy or skipped evidence.");
assert(logical(result.RuntimeStageWaveformsRequired) && ...
        logical(result.RuntimeStageWaveformsUsed) && ...
        logical(result.RuntimeChannelStateUsed) && ...
        ~logical(result.RuntimeSelfLoopWaveformsUsed), ...
    ["The timing regression must propagate every RA stage through the " ...
    "configured runtime channel; a self-loop waveform is not acceptable."]);

% The shared object's input clock must not be advanced twice using stale
% direction-specific counters when Msg1/2/3/4 alternate UL and DL.
final = result.RuntimeULChannelState;
assert(final.TotalObjectInputSamples == final.WarmupSamples + final.CurrentSampleIndex, ...
    "RA must maintain one exact shared channel input clock across all stages.");
assert(result.RuntimeDLChannelState.CurrentSampleIndex == final.CurrentSampleIndex, ...
    "Both returned TDD direction views must expose the final canonical clock.");

ok = true;
fprintf(['PASS testTDDCausalFourStepRARuntimeTiming: TDD Msg3 consumed ' ...
    'decoded TA and passed the measured CDL-A receiver without duplicate timing correction.\n']);
end

function localCleanup(pathText)
if isfolder(pathText)
    rmdir(pathText, "s");
end
end
