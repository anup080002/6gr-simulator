function ok = testTDDCausalFourStepRARuntimeTiming(runtimeSlot,scenarioPath)
%TESTTDDCAUSALFOURSTEPRARUNTIMETIMING Guard the shared RA timing boundary.
%
% The test uses the production TDD causal-wiring YAML, a concrete CDL-A
% runtime channel, physical antenna expansion, configured occupied-RE Es/N0, and
% the real Msg1/Msg2/Msg3/Msg4/RRCSetupComplete waveform chain.  It proves
% that decoded RAR timing advance drives Msg3 transmission and the PUSCH
% receiver acquires residual arrival from DM-RS, not injected timing truth.
% Explicit upstream receiver alignment is covered separately by
% testUntrimmedRAUplinkTiming and testDataReceiverSynchronizationAuthority.

if nargin < 1, runtimeSlot = 2; end
legacyFixture=nargin<2;
if legacyFixture
    scenarioPath = fullfile("simulator", "configs", "scenarios", ...
        "lls_causal_access_to_data_wiring_tdd.yaml");
end
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
expectedProfile="CDL-A"; referenceSNR=12;
if ~legacyFixture
    expectedProfile=string(scfg.get('channels.profile'));
    referenceSNR=double(scfg.get('simulation.snr_db'));
    assert(expectedProfile=="CDL-C" && ...
        scfg.get('global_radio_scope.carrier_frequency_hz')==4e9 && ...
        scfg.get('global_radio_scope.channel_bandwidth_hz')==100e6 && ...
        string(scfg.get('global_radio_scope.duplex_mode'))=="TDD", ...
        'The extended RA regression must use the actual 4-GHz/100-MHz TDD CDL-C scenario.');
end
runRoot = fullfile(pwd,'results','lls','tdd_causal_ra_identity', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(runRoot);
cfg = sixgr.config.normalizeConfig( ...
    sixgr.lls6g.buildInternalConfig(scfg, runRoot));
% This legacy standalone execution path still draws noise/payloads from
% the MATLAB stream. Use the authored scenario seed, not whichever state
% a preceding test happened to leave. Do not search for a passing seed.
savedRNG=rng;
rngCleanup=onCleanup(@()rng(savedRNG)); %#ok<NASGU>
rng(double(cfg.run.seed),'twister');

assert(strcmpi(string(sixgr.util.structGet(cfg, "phy.duplex.mode", "")), "TDD"), ...
    "The timing regression must exercise the YAML-selected TDD profile.");
assert(strcmpi(string(sixgr.util.structGet(cfg, "channel.model", "")), "CDL") && ...
        strcmpi(string(sixgr.util.structGet(cfg, "channel.cdlProfile", "")), expectedProfile) && ...
        strcmpi(string(sixgr.util.structGet(cfg, "channel.fading.profile", "")), expectedProfile), ...
    "The timing regression must preserve the concrete configured channel profile.");

multiUser = struct("Enabled", true, "NumUsers", 1, "RNTIStart", 1, ...
    "ExecutionModel", "slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfg, runRoot, multiUser, struct(), 1);
state.CurrentSlot = runtimeSlot;
state.CurrentServingIdx(:) = 1;
[cfgRuntime, ~] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
    cfg, state, 1, "UL");
% This isolated RA test starts after acquisition and does not execute an
% SSB selection receiver. Supply that boundary input explicitly; do not
% present a configured reference as a measured beam/activated TCI state.
referenceIndex = cfgRuntime.phy.ssb.runtimeSSBIndex;
sixgr.phy.ia.SSBBurstPlan.selectedPrecoderFromConfig(cfgRuntime,referenceIndex);
cfgRuntime.random_access.associated_ssb_index = referenceIndex;
cfgRuntime.random_access.associated_ssb_selection_source = ...
    "configured_SSB_reference_for_RA_timing_component_not_measured_selection";

% Reuse a previously materialized downlink channel, as the real SSB->RA
% transition does. Both direction views refer to one physical fading clock.
[state, dlState] = sixgr.truth.CoupledTruthRuntime.acquireRuntimeChannelStateForControl( ...
    state, cfgRuntime, 1, "DL");
[carrier, ~] = sixgr.phy.grid.makeCarrier(cfgRuntime);
txInfo = struct("OFDM", nrOFDMInfo(carrier));
nBS = double(cfgRuntime.lls6g.userContext.RuntimeServingBSAntennaMeta.NumElements);
nUE = double(cfgRuntime.lls6g.userContext.RuntimeUEAntennaMeta.NumElements);
if ~legacyFixture
    assert(carrier.NSizeGrid==273 && carrier.SubcarrierSpacing==30 && ...
        txInfo.OFDM.Nfft==4096 && txInfo.OFDM.SampleRate==122.88e6 && ...
        nBS==64 && nUE==4, ...
        'The H4 check must retain full-band numerology and 64-TXRU/four-chain dimensions.');
end
dlState = sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    dlState, cfgRuntime, complex(zeros(128, nBS)), txInfo, ...
    "NumTxAnt", nBS, "NumRxAnt", nUE, ...
    "TransmitAntennaRuntime", cfgRuntime.lls6g.userContext.RuntimeServingBSAntenna, ...
    "ReceiveAntennaRuntime", cfgRuntime.lls6g.userContext.RuntimeUEAntenna, ...
    "TransmitAntennaMeta", cfgRuntime.lls6g.userContext.RuntimeServingBSAntennaMeta, ...
    "ReceiveAntennaMeta", cfgRuntime.lls6g.userContext.RuntimeUEAntennaMeta);
state = sixgr.truth.CoupledTruthRuntime.commitRuntimeChannelState(state, dlState);
[~, ulState] = sixgr.truth.CoupledTruthRuntime.acquireRuntimeChannelStateForControl( ...
    state, cfgRuntime, 1, "UL");

[result, continuation] = sixgr.truth.CoupledTruthRuntime.runFourStepRARuntime(cfgRuntime, ...
    "RunFolder", runRoot, "RunId", "tdd_causal_ra_timing", ...
    "ScenarioName", "tdd_causal_ra_timing", ...
    "UEId", 1, "CellId", 1, "AttemptId", 1, ...
    "RuntimeNoiseSNR_dB", referenceSNR, ...
    "InitialDLChannelState", dlState, "InitialULChannelState", ulState, ...
    "RuntimeSlot", runtimeSlot, "WriteArtifacts", false, "StageAction", "prepare_next_stage");
assert(result.PreparedTransmission.AbsoluteSlot >= runtimeSlot-1, ...
    "A new RA attempt must not prepare an already elapsed PRACH occasion.");
plannedRA = continuation.RAConfig;
ownership = sixgr.phy.frame.CommonDLResourcePlan(cfgRuntime);
assert(plannedRA.TimingSchedule.CommonPDSCHReservationsValidated && ...
    ownership.checkPDSCH(plannedRA.Msg2PDSCH,plannedRA.Msg2Slot) && ...
    ownership.checkPDSCH(plannedRA.Msg4PDSCH,plannedRA.Msg4Slot));
fprintf('RA_RESOURCE_PLAN: Msg2=%d Msg3=%d Msg4=%d SetupComplete=%d rejected_resources=%d\n', ...
    plannedRA.Msg2Slot,plannedRA.Msg3Slot,plannedRA.Msg4Slot,plannedRA.SetupCompleteSlot, ...
    numel(plannedRA.TimingSchedule.RejectedResourceCandidates));
assert(result.RuntimeExecutionState == "pending_stage_receive" && ...
    isempty(result.RuntimeStageRows) && ~result.RACompleted && ~result.RRCConnected && ...
    result.RuntimeDLChannelState.CurrentSampleIndex == dlState.CurrentSampleIndex, ...
    "Preparing Msg1 must not propagate future samples or assert receiver success.");
assert(isequaln(result.RuntimeDLChannelState, dlState) && ...
    isequaln(result.RuntimeULChannelState, ulState), ...
    "Preparation must preserve complete channel identities, objects, and clocks, not empty result defaults.");
for completed = 0:4
    priorRows = result.RuntimeStageRows;
    nextStage = result.NextRuntimeStage;
    nextSlot = result.NextRuntimeStageSlot;
    transmission = result.PreparedTransmission;
    clockBefore = result.RuntimeDLChannelState.CurrentSampleIndex;
    objectInputBefore = result.RuntimeDLChannelState.TotalObjectInputSamples;
    rngBefore = rng;
    [waiting, continuation] = sixgr.truth.CoupledTruthRuntime.runFourStepRARuntime(cfgRuntime, ...
        "Continuation", continuation, "ReceiveThroughTime_s", ...
        transmission.EndTimeExclusive_s - 1/transmission.SampleRate_Hz);
    assert(waiting.RuntimeExecutionState == "pending_stage_receive" && ...
        isequaln(waiting.RuntimeStageRows, priorRows) && ...
        waiting.RuntimeDLChannelState.CurrentSampleIndex == clockBefore && ...
        waiting.RuntimeULChannelState.CurrentSampleIndex == clockBefore && ...
        waiting.RuntimeDLChannelState.TotalObjectInputSamples == objectInputBefore && ...
        isequaln(rng, rngBefore), ...
        "An incomplete receive interval must not advance the shared CDL object, consume noise, or publish a decode.");
    [result, continuation] = sixgr.truth.CoupledTruthRuntime.runFourStepRARuntime(cfgRuntime, ...
        "Continuation", continuation, "StopAfterStage", nextStage, ...
        "ReceiveThroughTime_s", transmission.EndTimeExclusive_s, ...
        "RuntimeSlot", nextSlot+1, ...
        "InitialDLChannelState", result.RuntimeDLChannelState, ...
        "InitialULChannelState", result.RuntimeULChannelState);
    assert(height(result.RuntimeStageRows) == completed+1 && ...
        isequaln(priorRows, result.RuntimeStageRows(1:completed,:)), ...
        "Resuming the physical TDD channel must not repeat or rewrite completed stage execution (completed=%d, received=%d).", ...
        completed, height(result.RuntimeStageRows));
    % A completed receiver stage must be visible before overall attachment.
    stageTables={'msg1_prach_detection','msg2_rar_trials','msg3_pusch_trials', ...
        'msg4_contention_resolution'};
    for stageIndex=1:4
        value=sixgr.util.structGet(result.ArtifactTables,stageTables{stageIndex},table());
        assert(height(value)==double(stageIndex<=completed+1), ...
            'Live RA artifacts must contain completed stages only, without waiting for final access.');
    end
    if completed==2
        assert(result.Msg3PUSCHCrcPass && result.RRCSetupRequestDecoded && ...
            strlength(result.RRCSetupRequestSHA256)>0 && ...
            result.RRCSetupRequestSHA256==string(continuation.Msg3Decoded.RRCSetupRequestSHA256) && ...
            ~result.RACompleted && ~result.RRCConnected, ...
            'A decoded Msg3 request must be published now without claiming completed Msg4/RRC attachment.');
        liveMsg3=result.ArtifactTables.msg3_pusch_trials;
        assert(liveMsg3.ULSCHCrcPass && liveMsg3.RRCSetupRequestDecoded && ...
            liveMsg3.RRCSetupRequestSHA256==result.RRCSetupRequestSHA256);
    end
    if completed>=1
        assert(~isempty(result.ArtifactTables.msg2_pdcch_candidates) && ...
            ~isempty(result.ArtifactTables.msg2_dci_fields), ...
            'Completed Msg2 candidate/DCI evidence must publish before attachment.');
    end
    if completed>=3
        assert(height(result.ArtifactTables.msg4_dci_fields)==24, ...
            'Received Msg4 DCI fields must not disappear between live and terminal publication.');
    end
    noiseRow=result.RuntimeStageRows(end,:);
    fprintf('RA %s %s: sample_SNR_dB=%.6f reference_mW=%.9g noise_mW=%.9g Fs_Hz=%.0f\n', ...
        nextStage,noiseRow.Direction,noiseRow.NoiseSNR_dB, ...
        noiseRow.DesiredReferencePowerBeforeNoise_mW,noiseRow.NoiseVariancePreFrontEnd_mW, ...
        noiseRow.ThermalSampleNoiseBandwidth_Hz);
    assert(noiseRow.WaveformAmplitudeUnit=="normalized_complex_baseband" && ...
        ~noiseRow.PhysicalDevicePowerClaim && ...
        isnan(noiseRow.AppliedTxPower_dBm) && ...
        isnan(noiseRow.NoiseVariancePreFrontEnd_mW) && ...
        noiseRow.NoiseVariancePreFrontEnd_re_UnitOccupiedRE_Es>0 && ...
        noiseRow.RequestedAWGNReferenceSNR_dB==referenceSNR && ...
        abs(noiseRow.NoiseSNR_dB-referenceSNR)<1e-10, ...
        ['Every UL/DL access stage must use the configured normalized ' ...
         'Es/N0 authority without claiming normalized values are mW/dBm.']);
    if completed < 4
        assert(result.RuntimeExecutionState=="pending_next_stage" && ~isempty(fieldnames(continuation)), ...
            'Actual %s reception failed before next-stage preparation: status=%s reason=%s sample_snr_db=%g.', ...
            nextStage,string(result.RuntimeExecutionState),string(result.FailureReason),noiseRow.NoiseSNR_dB);
        decodedClock = result.RuntimeDLChannelState.CurrentSampleIndex;
        decodedRows = result.RuntimeStageRows;
        if completed==0
            assert(isnan(result.TimingAdvanceCommand) && isnan(result.TimingAdvanceSamples), ...
                'A PRACH gNB estimate must not be presented as a received UE timing command.');
        elseif completed==1
            assert(result.TimingAdvanceCommand==continuation.RARRx.TimingAdvanceCommand);
            % Poison stale diagnostic/sample caches, not the received RAR.
            % The next actual Msg3 TX must derive TA from decoded MAC bytes.
            continuation.Result.TimingAdvanceSamples=123456;
            continuation.TimingAdvance.TimingAdvanceSamples=234567;
        end
        [result, continuation] = sixgr.truth.CoupledTruthRuntime.runFourStepRARuntime(cfgRuntime, ...
            "Continuation", continuation, "StageAction", "prepare_next_stage");
        assert(result.RuntimeExecutionState == "pending_stage_receive" && ...
            result.RuntimeDLChannelState.CurrentSampleIndex == decodedClock && ...
            isequaln(result.RuntimeStageRows, decodedRows), ...
            "Preparing the next RA stage must not advance the physical fading clock or add received evidence.");
        if completed==1
            timing = sixgr.phy.ra.resolveRARTimingAdvance(continuation.RARRx.TimingAdvanceCommand, ...
                continuation.RAConfig.CarrierSCSkHz,result.PreparedTransmission.SampleRate_Hz);
            assert(result.TimingAdvanceSamples==timing.Samples && ...
                result.TimingAdvanceNTA_Tc==timing.NTA_Tc && ...
                result.TimingAdvanceSource=="received_MAC_RAR_absolute_command_ts_38_213_4_2");
        end
    end
end
assert(isempty(fieldnames(continuation)) && result.RuntimeExecutionState == "terminal");
% Export the actual receiver-produced Msg3 timing row and verify its CSV
% round-trip; this is diagnostic test output, not a production run artifact.
timingRow = result.ArtifactTables.msg3_pusch_trials;
assert(timingRow.TimingAdvanceCommand==result.TimingAdvanceCommand && ...
    timingRow.TimingAdvanceSamples==result.TimingAdvanceSamples && ...
    timingRow.TimingAdvanceNTA_Tc==result.TimingAdvanceNTA_Tc && ...
    timingRow.TimingAdvanceSampleRate_Hz==result.TimingAdvanceSampleRate_Hz);
timingCSV = fullfile(runRoot,'measured_msg3_timing.csv');
msg4Fields = result.ArtifactTables.msg4_dci_fields;
assert(height(msg4Fields)==24 && sum(msg4Fields.Endpoint=="UE_RX")==12);
assert(all(msg4Fields.AbsoluteSlot==plannedRA.Msg4Slot));
msg4Row = result.ArtifactTables.msg4_contention_resolution;
assert(strlength(result.Msg3PayloadHex)>0 && ...
    result.Msg3PayloadHex==result.Msg3TransmittedPayloadHex && ...
    strlength(result.Msg4PayloadHex)>0 && ...
    result.Msg4PayloadHex==result.Msg4TransmittedPayloadHex);
assert(msg4Row.MACEncodingProfile=="legacy_bounded_not_NR_MAC_RRC" && ...
    ~msg4Row.MACRRCStandardsQualified, ...
    'A bit-exact TC-RNTI PHY must not promote the bounded MAC/RRC body to NR protocol qualification.');
sixgr.util.csvWriteTable(fullfile(runRoot,'measured_msg4_dci_fields.csv'),msg4Fields);
sixgr.util.csvWriteTable(timingCSV,timingRow);
roundTrip = readtable(timingCSV,'TextType','string');
assert(roundTrip.TimingAdvanceNTA_Tc==timingRow.TimingAdvanceNTA_Tc && ...
    roundTrip.TimingAdvanceSource==string(timingRow.TimingAdvanceSource));
noiseCSV=fullfile(runRoot,'measured_ra_stage_noise.csv');
sixgr.util.csvWriteTable(noiseCSV,result.RuntimeStageRows);
noiseRows=readtable(noiseCSV,'TextType','string');
noiseNames=string(noiseRows.Properties.VariableNames);
absoluteTxAbsentOrNA=~ismember("AppliedTxPower_dBm",noiseNames) || ...
    all(isnan(noiseRows.AppliedTxPower_dBm));
absoluteNoiseAbsentOrNA=~ismember("NoiseVariancePreFrontEnd_mW",noiseNames) || ...
    all(isnan(noiseRows.NoiseVariancePreFrontEnd_mW));
assert(height(noiseRows)==5 && ...
    all(~noiseRows.PhysicalDevicePowerClaim) && ...
    absoluteTxAbsentOrNA && absoluteNoiseAbsentOrNA && ...
    all(noiseRows.NoiseVariancePreFrontEnd_re_UnitOccupiedRE_Es>0) && ...
    all(noiseRows.RequestedAWGNReferenceSNR_dB==referenceSNR) && ...
    all(abs(noiseRows.NoiseSNR_dB-referenceSNR)<1e-10));
assert(all(abs(noiseRows.NoiseSNR_dB - 10*log10( ...
    noiseRows.DesiredReferencePowerBeforeNoise_re_UnitOccupiedRE_Es./ ...
    noiseRows.NoiseVariancePreFrontEnd_re_UnitOccupiedRE_Es)) < 1e-10) && ...
    all(contains(noiseRows.NoiseSNRSource,'not_UE_report')), ...
    'Access CSV SNR must close on actual sample-power/noise quantities, not merely the requested label.');
assert(result.ArtifactTables.msg1_prach_detection.TimingAdvanceRole == ...
    "gnb_proposed_rar_command_not_yet_ue_received" && ...
    result.ArtifactTables.msg2_rar_trials.TimingAdvanceCommand==result.TimingAdvanceCommand);
assert(result.PowerControlStatus == ...
    "not_applied_normalized_fixed_esn0_unit_occupied_re_es" && ...
    result.PreambleTxAmplitudeScale==1 && result.Msg2TxAmplitudeScale==1 && ...
    result.Msg3TxAmplitudeScale==1 && result.Msg4TxAmplitudeScale==1 && ...
    result.SetupCompleteTxAmplitudeScale==1, ...
    'Normalized fixed-Es/N0 RA must not mix in absolute 38.213/device-power scaling.');

assert(logical(result.RACompleted) && logical(result.StrictOk), ...
    "The TDD measured four-step RA waveform chain must complete strictly.");
assert(logical(result.Msg3PUSCHCrcPass), ...
    "Msg3 PUSCH must decode through the production configured CDL receiver chain.");
assert(logical(result.Msg3TimingAdvanceApplied), ...
    "Msg3 must consume the timing advance decoded from Msg1/RAR state.");
assert(logical(result.Msg3TimingEstimateUsed) && ...
        isfinite(double(result.Msg3RawTimingEstimate_samples)) && ...
        result.Msg3AppliedTimingCorrection_samples==result.Msg3RawTimingEstimate_samples, ...
    "A decoded TA command is not proof of zero residual arrival; require receiver timing evidence.");
assert(string(result.Msg3TimingEstimateSource) == ...
        "nrTimingEstimate_dmrs" && ...
        timingRow.AppliedTimingCorrection_samples==result.Msg3AppliedTimingCorrection_samples && ...
        timingRow.TimingEstimateUsed && ...
        string(timingRow.TimingEstimateSource)==string(result.Msg3TimingEstimateSource), ...
    "The actual Msg3 residual timing acquisition must survive runtime and CSV publication.");
assert(logical(result.Msg3ChannelEstimateAvailable) && ...
        logical(result.Msg3EqualizationAvailable) && ...
        logical(result.Msg3LLRFinite), ...
    "Msg3 must retain measured channel-estimation, equalization, and finite-LLR evidence.");
assert(~logical(result.ProxyUsed) && ~logical(result.Skipped), ...
    "The TDD RA timing regression must not use proxy or skipped evidence.");
assert(logical(result.RuntimeStageWaveformsRequired) && ...
        logical(result.RuntimeStageWaveformsUsed) && ...
        logical(result.RuntimeChannelStateUsed) && ...
        ~logical(result.RuntimeSelfLoopWaveformsUsed), ...
    ["The timing regression must propagate every RA stage through the " ...
    "configured runtime channel; a self-loop waveform is not acceptable."]);

% The shared object's input clock must not be advanced twice using stale
% direction-specific counters when Msg1/2/3/4 alternate UL and DL.
final = result.RuntimeULChannelState;
assert(final.TotalObjectInputSamples == final.WarmupSamples + final.CurrentSampleIndex, ...
    "RA must maintain one exact shared channel input clock across all stages.");
assert(result.RuntimeDLChannelState.CurrentSampleIndex == final.CurrentSampleIndex, ...
    "Both returned TDD direction views must expose the final canonical clock.");

% Counter agreement alone is insufficient: both views could agree on the
% wrong absolute epoch. Check each executed waveform against its declared
% zero-based stage slot, using the actual OFDM sample rate.
stages = result.RuntimeStageRows;
assert(height(stages) == 5, "All five executed RA/RRC stages need timing evidence.");
fs = double(txInfo.OFDM.SampleRate);
expectedStart = round(double(stages.StageSlot) * sixgr.time.slotDurationSec(cfgRuntime) * fs);
assert(all(double(stages.RuntimeChannelStartSample) == expectedStart), ...
    "RA waveform samples must start at their scheduled absolute slot, not a silently clamped later time.");
assert(all(double(stages.RuntimeChannelEndSample) - ...
    double(stages.RuntimeChannelStartSample) == double(stages.TxSampleCount)), ...
    "RA sample intervals must equal the actual transmitted waveform lengths.");

% Bind the access ledger to these actual executed waveform coordinates,
% rather than reconstructing stage times from the current caller slot.
trial = struct("Status", "PASS", "CRCPass", NaN, "Slot", stages.StageSlot(end)+1, ...
    "FullRAEvidenceSource", "sixgr.phy.ra.runFourStepRA");
for name = ["RASlotTimeBase", "Msg1ScheduledSlot", "Msg2ScheduledSlot", ...
        "Msg3ScheduledSlot", "Msg4ScheduledSlot", "SetupCompleteScheduledSlot", ...
        "RACompleted", "RequireRRCSetupComplete", "RRCSetupRequestDecoded", ...
        "RRCSetupDecoded", "SRB1Installed", "RRCSetupCompleteCRC", ...
        "RRCSetupCompleteDecoded", "RRCConnected", "RRCSetupCompletePayloadSHA256", ...
        "RAPIDMatches","Msg2DCICrcPass","Msg2PDSCHCrcPass","RARULGrantValid", ...
        "Msg3PUSCHCrcPass","Msg4PDCCHCrcPass","Msg4PDSCHCrcPass", ...
        "ContentionIdentityMatches","TemporaryCRNTI","FinalCRNTI", ...
        "FinalCRNTISource","FinalCRNTIEncodingProfile"]
    trial.(name) = result.(name);
end
state.CurrentSlot = trial.Slot;
state = sixgr.truth.CoupledTruthRuntime.applyPRACHTrial(state, 1, struct2table(trial));
assert(sixgr.truth.CoupledRadioIdentity.resolve(state,1)==result.FinalCRNTI && ...
    state.RadioIdentityBindings.RNTI==result.TemporaryCRNTI, ...
    'The runtime must retain the radio identity from actual decoded access.');
[connectedCfg,~]=sixgr.truth.CoupledTruthRuntime.applyUserContext(cfgRuntime,state,1,"UL");
assert(connectedCfg.phy.pdsch.RNTI==result.FinalCRNTI && ...
    connectedCfg.phy.pusch.RNTI==result.FinalCRNTI, ...
    'Future connected DL/UL PHY contexts must share the actually received access identity.');
identityEvidence=struct('ReceivedAccessRow',trial,'RuntimeStages',stages, ...
    'InstalledIdentity',state.RadioIdentityBindings, ...
    'ConnectedDLRNTI',connectedCfg.phy.pdsch.RNTI, ...
    'ConnectedULRNTI',connectedCfg.phy.pusch.RNTI);
save(fullfile(runRoot,'received_radio_identity.mat'),'identityEvidence');
sixgr.util.csvWriteTable(fullfile(runRoot,'received_radio_identity.csv'), ...
    struct2table(state.RadioIdentityBindings),'PreserveSchema',true);
fprintf('RECEIVED_RADIO_IDENTITY_EVIDENCE=%s\n',runRoot);
events = state.InitialAccessLifecycleTraceTable;
raEvents = ["PRACH_MSG1_DETECTED", "MSG2_RAR_DECODED", "MSG3_PUSCH_COMPLETED", ...
    "MSG4_CONTENTION_RESOLUTION_COMPLETED", "RRC_SETUP_COMPLETE_ACCEPTED"];
for k = 1:numel(raEvents)
    event = events(string(events.EventName) == raEvents(k), :);
    assert(height(event) == 1 && event.SourceRASlot == stages.StageSlot(k) && ...
        event.SourceRASlotTimeBase == "absolute_zero_based" && ...
        event.CanonicalSlot == stages.StageSlot(k)+1 && ...
        event.Slot == stages.StageSlot(k)+1, ...
        "The lifecycle event must identify its actual received RA stage, with an explicit zero-to-one-based conversion.");
end

% Physical clock agreement must be paired with legal duplex allocations.
ra = sixgr.mac.ra.RAConfig(cfgRuntime, "RuntimeSlot", runtimeSlot);
frame = sixgr.phy.FrameStructureEngine(cfgRuntime,"FrameCoreOnly",true);
assert(frame.IsDLAllocation(ra.Msg2Slot,[ra.Msg2PDSCH.SymbolStart ra.Msg2PDSCH.NumSymbols]));
assert(frame.IsULAllocation(ra.Msg3Slot,[ra.Msg3PUSCH.SymbolStart ra.Msg3PUSCH.NumSymbols]));
assert(frame.IsDLAllocation(ra.Msg4Slot,[ra.Msg4PDSCH.SymbolStart ra.Msg4PDSCH.NumSymbols]));
assert(frame.IsULAllocation(ra.SetupCompleteSlot,[ra.SetupCompletePUSCH.SymbolStart ra.SetupCompletePUSCH.NumSymbols]));
assert(ra.Msg3Slot == ra.Msg2Slot + ra.TimingSchedule.Msg3K2Slots + ...
    ra.TimingSchedule.Msg3AdditionalDelaySlots);

ok = true;
fprintf(['PASS testTDDCausalFourStepRARuntimeTiming: decoded RAR TA=%g, NTA=%g Tc, ' ...
    '%g samples at %g Hz; configured CDL Msg3 CRC passed with receiver-derived residual timing.\n'], ...
    result.TimingAdvanceCommand,result.TimingAdvanceNTA_Tc,result.TimingAdvanceSamples,result.TimingAdvanceSampleRate_Hz);
end
