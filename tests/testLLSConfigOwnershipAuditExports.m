function ok = testLLSConfigOwnershipAuditExports()
%TESTLLSCONFIGOWNERSHIPAUDITEXPORTS Verify config-ownership audit artifacts are emitted canonically.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_3bs_30ue_tdlc_browser_coupled.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));

artifacts = sixgr.truth.exportLLSConfigOwnershipArtifacts(fullfile(tmp, "run"), scfg, cfg);

mustExist = { ...
    char(artifacts.HardcodedParameterAudit)
    char(artifacts.ConfigOwnershipMatrix)
    char(artifacts.RuntimeValueSourceDictionary)
    char(artifacts.ConfigExposureSummary)
    char(artifacts.ConfigRoundtripVerification)
    char(artifacts.BrowserRuntimeDBConsistency)
    char(artifacts.SummaryVsRawConsistency)
    char(artifacts.ValueSourceAudit)
    char(artifacts.RuntimeConfigApplicationEvidence)
    char(artifacts.ParameterBindingMatrix)
    char(artifacts.BrowserConfigSurfaceMatrix)
    char(artifacts.FeatureParameterIndex)
    char(artifacts.ConfigStatusSummary)
    char(artifacts.UIFeatureFilterAudit)};
for i = 1:numel(mustExist)
    assert(exist(mustExist{i}, "file") == 2, "Missing config-ownership artifact: %s", mustExist{i});
end

auditT = localReadVerificationCSV(char(artifacts.HardcodedParameterAudit));
matrixT = localReadVerificationCSV(char(artifacts.ConfigOwnershipMatrix));
dictT = localReadVerificationCSV(char(artifacts.RuntimeValueSourceDictionary));
exposureT = localReadVerificationCSV(char(artifacts.ConfigExposureSummary));
roundtripT = localReadVerificationCSV(char(artifacts.ConfigRoundtripVerification));
browserDbT = localReadVerificationCSV(char(artifacts.BrowserRuntimeDBConsistency));
summaryRawT = localReadVerificationCSV(char(artifacts.SummaryVsRawConsistency));
valueSourceAuditT = localReadVerificationCSV(char(artifacts.ValueSourceAudit));
applicationEvidenceT = localReadVerificationCSV(char(artifacts.RuntimeConfigApplicationEvidence));
bindingT = localReadVerificationCSV(char(artifacts.ParameterBindingMatrix));
browserSurfaceT = localReadVerificationCSV(char(artifacts.BrowserConfigSurfaceMatrix));
featureIndexT = localReadVerificationCSV(char(artifacts.FeatureParameterIndex));
statusSummaryT = localReadVerificationCSV(char(artifacts.ConfigStatusSummary));
filterAuditT = localReadVerificationCSV(char(artifacts.UIFeatureFilterAudit));

assert(all(ismember(["ScenarioID","ConfigHash","RunnerProfile","File","Function","ParameterOrConstant","Classification","OwnerShouldBe","ActionTaken","StatusAfterPatch"], ...
    string(auditT.Properties.VariableNames))), ...
    "Hardcoded-parameter audit must expose canonical ownership fields.");
assert(all(ismember(["ParameterName","ConfiguredValue","ResolvedRuntimeValue","BrowserExposed","YAMLExposed","RuntimeDerived","HiddenFallbackRemoved","SourceOfTruth","CanonicalArtifact"], ...
    string(matrixT.Properties.VariableNames))), ...
    "Config-ownership matrix must expose canonical ownership columns.");
assert(all(ismember(["Category","ResolvedMATLABPath","RuntimeConsumer","OwnershipClass","Definition"], ...
    string(matrixT.Properties.VariableNames))), ...
    "Config-ownership matrix must expose expanded ownership trace columns.");
assert(all(ismember(["FieldName","ValueSource","ValueRole","ValueStatus","ValueDefinition","FinalizedFlag","PlaceholderFlag","FallbackFlag","NAReason","CanonicalArtifacts"], ...
    string(dictT.Properties.VariableNames))), ...
    "Runtime value-source dictionary must expose source/role/status semantics.");
assert(all(ismember(["Category","ParameterName","BrowserExposed","YAMLExposed","RuntimeDerived","HiddenFallbackRemoved","OwnershipClass","SourceOfTruth","CanonicalArtifact","RuntimeConsumer","Definition"], ...
    string(exposureT.Properties.VariableNames))), ...
    "Config exposure summary must expose canonical exposure columns.");
assert(all(ismember(["ParameterName","BrowserSubmittedValue","RuntimeOverlayValue","ResolvedMATLABValue","RuntimeConsumer","DBSnapshotValue","ExportedCSVValue","BrowserDisplayedValue","ConsistencyStatus"], ...
    string(roundtripT.Properties.VariableNames))), ...
    "Config roundtrip verification must expose the canonical browser-overlay-runtime-DB-CSV-browser chain columns.");
assert(all(ismember(["ParameterName","DBSnapshotValue","DBLogicalPath","ExportedCSVLogicalPath","ExportedCSVValue","BrowserPayloadField","BrowserDisplayedValue","ConsistencyStatus"], ...
    string(browserDbT.Properties.VariableNames))), ...
    "Browser/runtime/DB consistency must expose DB, CSV, and browser payload lineage columns.");
assert(all(ismember(["SummaryField","SummaryValue","RawDerivedValue","ConsistencyStatus"], ...
    string(summaryRawT.Properties.VariableNames))), ...
    "Summary-vs-raw consistency must expose summary/raw comparison columns.");
assert(all(ismember(["FieldName","ObservedValue","SourceArtifact","ValueSource","ValueRole","ValueStatus","ConsistencyStatus"], ...
    string(valueSourceAuditT.Properties.VariableNames))), ...
    "Value-source audit must expose observed value, source, role, status, and consistency columns.");
assert(all(ismember(["ParameterId","FeatureFamily","InternalCfgPath","ConsumerFunction","AppliedValue","EvidenceStatus"], ...
    string(applicationEvidenceT.Properties.VariableNames))), ...
    "Runtime config application evidence must expose parameter, consumer, and applied-value provenance.");
assert(all(ismember(["ParameterId","FeatureFamily","UILayer","UISection","BrowserPath","ScenarioPath","InternalCfgPath", ...
    "BrowserVisible","BrowserEditable","SubmittedValue","ResolvedScenarioValue","InternalCfgValue","MappingStatus", ...
    "RuntimeAppliedStatus","RuntimeMeasuredStatus","FinalBindingStatus"], string(bindingT.Properties.VariableNames))), ...
    "Parameter binding matrix must expose browser/scenario/cfg/runtime binding status columns.");
assert(all(ismember(["ParameterId","UILabel","UISection","FeatureFamily","DisplayedValue","SubmittedValue","ResolvedMATLABValue", ...
    "RuntimeAppliedValue","RuntimeMeasuredValue","ConfigStatus","ApplicationStatus","MeasurementStatus","DisplayStatus","DisplayReason"], ...
    string(browserSurfaceT.Properties.VariableNames))), ...
    "Browser config surface matrix must expose browser display semantics.");
assert(all(ismember(["FeatureFamily","UILayer","UISection","ParameterCount","RuntimeAppliedCount","RuntimeMeasuredCount"], ...
    string(featureIndexT.Properties.VariableNames))), ...
    "Feature parameter index must expose feature-family counts.");
assert(all(ismember(["FinalBindingStatus","ConfigResolvedStatus","RuntimeAppliedStatus","RuntimeMeasuredStatus","ParameterCount"], ...
    string(statusSummaryT.Properties.VariableNames))), ...
    "Config status summary must expose final/config/applied/measured status counts.");
assert(all(ismember(["FeatureFamily","ParameterId","UISection","SelectionBucket","ExclusionReason"], ...
    string(filterAuditT.Properties.VariableNames))), ...
    "UI feature filter audit must expose inclusion/exclusion decisions.");

assert(any(strcmp(string(matrixT.ParameterName), "run_control.num_workers") & localTruthMask(matrixT.HiddenFallbackRemoved)), ...
    "Config-ownership matrix must record hidden-fallback removal for run_control.num_workers.");
assert(any(strcmp(string(matrixT.ParameterName), "harq.max_retx") & localTruthMask(matrixT.HiddenFallbackRemoved)), ...
    "Config-ownership matrix must record hidden-fallback removal for harq.max_retx.");
assert(any(strcmp(string(dictT.FieldName), "AppliedPrecoderPMI") & strcmp(string(dictT.ValueRole), "applied")), ...
    "Runtime value-source dictionary must preserve applied precoder lineage.");
mobilityMask = strcmp(string(matrixT.ParameterName), "mobility.ue_speed_kmh");
assert(nnz(mobilityMask) == 1, "Config-ownership matrix must expose mobility.ue_speed_kmh exactly once.");
assert(strcmp(string(matrixT.ResolvedRuntimeValue(find(mobilityMask, 1, "first"))), "30"), ...
    "mobility.ue_speed_kmh must resolve to configured speed rather than derived Doppler.");
assert(height(matrixT) >= 100, "Config-ownership matrix must cover a substantial LLS parameter surface.");
assert(height(dictT) >= 50, "Runtime value-source dictionary must cover a substantial LLS runtime/export surface.");
assert(height(exposureT) == height(matrixT), "Config exposure summary should cover the full ownership matrix surface.");
assert(height(roundtripT) >= 90, "Config roundtrip verification must cover a substantial LLS parameter surface.");
assert(any(strcmp(string(matrixT.Category), "radio_timing")), ...
    "Config-ownership matrix must include radio/numerology timing parameters.");
assert(any(strcmp(string(matrixT.Category), "harq")), ...
    "Config-ownership matrix must include HARQ ownership parameters.");
assert(any(strcmp(string(matrixT.Category), "pucch_trs")), ...
    "Config-ownership matrix must include PUCCH/TRS ownership parameters.");
assert(any(strcmp(string(matrixT.Category), "exports")), ...
    "Config-ownership matrix must include export/backend ownership parameters.");
assert(any(strcmp(string(matrixT.ParameterName), "frequency.center_frequency_hz")), ...
    "Config-ownership matrix must include carrier center frequency ownership.");
assert(any(strcmp(string(matrixT.ParameterName), "frame.scs_khz")), ...
    "Config-ownership matrix must include subcarrier spacing ownership.");
assert(any(strcmp(string(matrixT.ParameterName), "reference_signals.trs.num_ports")), ...
    "Config-ownership matrix must include TRS port ownership.");
assert(any(strcmp(string(matrixT.ParameterName), "receiver.use_ideal_timing_sync") & localTruthMask(matrixT.HiddenFallbackRemoved)), ...
    "Config-ownership matrix must record hidden-fallback removal for receiver.use_ideal_timing_sync.");
assert(any(strcmp(string(matrixT.ParameterName), "control_gating.srs_max_age_slots") & localTruthMask(matrixT.HiddenFallbackRemoved)), ...
    "Config-ownership matrix must record hidden-fallback removal for control_gating.srs_max_age_slots.");
assert(any(strcmp(string(matrixT.ParameterName), "link_adaptation.cqi_table") & localTruthMask(matrixT.HiddenFallbackRemoved)), ...
    "Config-ownership matrix must record hidden-fallback removal for link_adaptation.cqi_table.");
assert(any(strcmp(string(matrixT.ParameterName), "csi_acquisition_and_reporting.channel_state_information_mode") & localTruthMask(matrixT.HiddenFallbackRemoved)), ...
    "Config-ownership matrix must record hidden-fallback removal for CSI feedback-mode ownership.");
assert(any(strcmp(string(matrixT.ParameterName), "output.backend")), ...
    "Config-ownership matrix must include export backend ownership.");
assert(any(strcmp(string(matrixT.ParameterName), "link_adaptation.fixed_or_amc")), ...
    "Config-ownership matrix must include link-adaptation mode ownership.");
linkModeMask = strcmp(string(matrixT.ParameterName), "link_adaptation.fixed_or_amc");
assert(nnz(linkModeMask) == 1 && strcmp(string(matrixT.ResolvedRuntimeValue(find(linkModeMask, 1, "first"))), "amc"), ...
    "link_adaptation.fixed_or_amc must resolve to the configured AMC mode.");
mobilityDict = dictT(strcmp(string(dictT.FieldName), "MobilitySpeed_kmh"), :);
assert(height(mobilityDict) == 1, "Runtime value-source dictionary must include MobilitySpeed_kmh exactly once.");
assert(strcmp(string(mobilityDict.ValueSource), "resolved_scenario_mobility_speed"), ...
    "MobilitySpeed_kmh must keep a speed-specific value source.");
assert(strcmp(string(mobilityDict.ValueRole), "configured"), ...
    "MobilitySpeed_kmh must remain a configured speed value, not a Doppler-derived value.");
dopplerDict = dictT(strcmp(string(dictT.FieldName), "ResolvedDopplerHz"), :);
assert(height(dopplerDict) == 1, "Runtime value-source dictionary must include ResolvedDopplerHz exactly once.");
assert(strcmp(string(dopplerDict.ValueSource), "carrier_frequency_and_mobility_speed_derivation"), ...
    "ResolvedDopplerHz must keep a derivation-specific value source.");
assert(strcmp(string(dopplerDict.ValueRole), "derived"), ...
    "ResolvedDopplerHz must remain a derived Doppler value.");
assert(~strcmpi(string(mobilityDict.ValueSource), string(dopplerDict.ValueSource)), ...
    "Speed and Doppler must never share the same value-source mapping.");
assert(any(strcmp(string(dictT.FieldName), "UseIdealTimingSync") & strcmp(string(dictT.ValueRole), "resolved")), ...
    "Runtime value-source dictionary must expose receiver timing-sync policy as resolved runtime config.");
assert(any(strcmp(string(dictT.FieldName), "TRSGatingActive") & strcmp(string(dictT.ValueRole), "resolved")), ...
    "Runtime value-source dictionary must expose resolved TRS gating state.");
assert(any(strcmp(string(roundtripT.ParameterName), "deployment_topology.inter_site_distance")), ...
    "Config roundtrip verification must include deployment topology parameters.");
assert(any(strcmp(string(roundtripT.ParameterName), "channels.doppler_source_mode")), ...
    "Config roundtrip verification must include channel ownership parameters.");
assert(any(strcmp(string(roundtripT.ParameterName), "control_gating.trs_required")), ...
    "Config roundtrip verification must include control-gating parameters.");
assert(any(strcmp(string(roundtripT.ParameterName), "receiver.use_ideal_timing_sync")), ...
    "Config roundtrip verification must include receiver timing-sync ownership.");
assert(any(strcmp(string(roundtripT.ParameterName), "link_adaptation.cqi_table")), ...
    "Config roundtrip verification must include CQI-table ownership.");
assert(any(strcmp(string(roundtripT.ParameterName), "users.beam_selection_strategy")), ...
    "Config roundtrip verification must include beam/precoding ownership parameters.");
assert(any(strcmp(string(bindingT.ParameterId), "random_access.configuration_index")), ...
    "Parameter binding matrix must include PRACH configuration_index.");
assert(any(strcmp(string(browserSurfaceT.ParameterId), "random_access.configuration_index")), ...
    "Browser config surface matrix must include PRACH configuration_index.");
assert(any(strcmp(string(featureIndexT.FeatureFamily), "Random_Access_PRACH")), ...
    "Feature parameter index must include the PRACH feature family.");
browserVisibleMask = localTruthMask(bindingT.BrowserVisible);
assert(~any(browserVisibleMask & strcmp(string(bindingT.UISection), "Uncategorized")), ...
    "Browser-visible parameters must not fall back to an uncategorized UI section.");
assert(~any(browserVisibleMask & strcmp(string(bindingT.FeatureFamily), "Uncategorized")), ...
    "Browser-visible parameters must not fall back to an uncategorized feature family.");
appliedMask = strcmp(string(bindingT.RuntimeAppliedStatus), "applied_to_runtime_object");
if any(appliedMask)
    assert(all(ismember(string(bindingT.ParameterId(appliedMask)), string(applicationEvidenceT.ParameterId))), ...
        "Every runtime-applied binding row must be backed by a published runtime config application evidence row.");
else
    assert(isempty(applicationEvidenceT) || ~any(strcmp(string(applicationEvidenceT.EvidenceStatus), "applied_to_runtime_object")), ...
        "Config-only ownership export must not fabricate runtime-applied evidence rows.");
end
assert(~any(strcmp(string(browserSurfaceT.DisplayReason), "unavailable until runtime evidence is published")), ...
    "Browser config surface must use explicit resolved/applied/measured reasons instead of the old ambiguous unavailable wording.");

ok = true;
end

function mask = localTruthMask(values)
vals = lower(strtrim(string(values)));
mask = vals == "1" | vals == "true";
end

function T = localReadVerificationCSV(filePath)
opts = detectImportOptions(filePath, "Delimiter", ",");
opts.VariableNamingRule = "preserve";
opts = setvartype(opts, opts.VariableNames, "string");
T = readtable(filePath, opts);
end
