function ok = testPDSCHTwoCodewordHARQContext()
%TESTPDSCHTWOCODEWORDHARQCONTEXT One TB context per rank-5+ codeword.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
layouts = { ...
    localLayout(928, 0.30, 0, 2, 6000), ...
    localLayout(1416, 0.30, 0, 3, 9000)};
grant = localGrant(0, false);
meta = localMeta(grant, layouts, struct(), false, [0 0], false);
[group, status] = sixgr.harq.validateCodewordTBContexts(meta);

assert(string(group.ContractVersion) == "HARQCodewordContextGroup/v1" ...
    && double(group.CodewordCount) == 2, ...
    "Rank-5+ HARQ must expose an explicit two-codeword context group.");
assert(isequal(double(group.TBSBitsPerCodeword), [928 1416]) ...
    && double(group.TBSBits) == 2344, ...
    "Per-codeword TBS ownership and the explicitly aggregate total differ.");
assert(numel(group.CodewordContexts) == 2 ...
    && double(group.CodewordContexts{1}.CodewordId) == 0 ...
    && double(group.CodewordContexts{2}.CodewordId) == 1 ...
    && double(group.CodewordContexts{1}.TBSBits) == 928 ...
    && double(group.CodewordContexts{2}.TBSBits) == 1416, ...
    "Each codeword must retain its own HARQ TB identity and TBS.");
assert(double(status.OriginalTBSBits) == 2344 ...
    && isequal(double(status.OriginalTBSBitsPerCodeword), [928 1416]) ...
    && strlength(string(status.HARQContextHash)) == 64, ...
    "Group status must label both per-codeword values and aggregate totals.");

retxGrant = localGrant(2, true);
retxMeta = localMeta(retxGrant, layouts, group, true, [2 2], true);
[retxGroup, retxStatus] = ...
    sixgr.harq.validateCodewordTBContexts(retxMeta);
assert(contains(string(retxStatus.HARQContextStatus), ...
    "retransmission_validated") ...
    && isequal(double(retxGroup.TBSBitsPerCodeword), [928 1416]), ...
    "Two-codeword retransmission must validate each unchanged TB context.");

bad = meta;
bad.ExpectedTBSBitsPerCodeword = [928 1417];
localAssertThrows(@() sixgr.harq.validateCodewordTBContexts(bad), ...
    "sixgr:harq:TBSMismatch");

ok = true;
fprintf("PDSCH two-codeword HARQ: 2 TB contexts, aggregate 2344 bits, typed mismatch guard PASS\n");
end

function meta = localMeta(grant, layouts, previous, isRetx, rv, soft)
meta = struct( ...
    "Direction", "DL", ...
    "Grant", grant, ...
    "CodingLayouts", {layouts}, ...
    "PreviousContext", previous, ...
    "IsRetransmission", logical(isRetx), ...
    "RateMatchedBitsTotalPerCodeword", [6000 9000], ...
    "RateMatchedBitsPerCBPerCodeword", ...
        {{double(layouts{1}.E_r), double(layouts{2}.E_r)}}, ...
    "TBSBitsPerCodeword", [928 1416], ...
    "ExpectedTBSBitsPerCodeword", [928 1416], ...
    "RVPerCodeword", double(rv), ...
    "RVSequence", [0 2 3 1], ...
    "SoftCombiningEvidenceAvailablePerCodeword", ...
        repmat(logical(soft), 1, 2));
end

function grant = localGrant(rv, isRetx)
grant = struct( ...
    "Direction", "DL", ...
    "ServingCell", 1, ...
    "UEIndex", 1, ...
    "RNTI", 101, ...
    "TransportBlockId", "rank5_tb_group", ...
    "TBId", "rank5_tb_group", ...
    "TBSBits", 2344, ...
    "TBSBitsPerCodeword", [928 1416], ...
    "TransportBlockSize", 2344, ...
    "TargetCodeRate", 0.30, ...
    "Modulation", "64QAM", ...
    "NumLayers", 5, ...
    "PRBSet", 0:23, ...
    "SymbolAllocation", [0 14], ...
    "MappingType", "A", ...
    "CodedBitCountG", 15000, ...
    "HARQ", struct("HARQProcess", 0, "HarqID", 0, ...
        "NDI", true, "NDIEpoch", 1, "RV", double(rv), ...
        "IsRetransmission", logical(isRetx)), ...
    "IsRetransmission", logical(isRetx));
end

function layout = localLayout(tbs, rate, rv, layers, E)
layout = sixgr.phy.phycode.resolveCodingLayout( ...
    "Direction", "DL", ...
    "TransportBlockSize", double(tbs), ...
    "TargetCodeRate", double(rate), ...
    "RV", double(rv), ...
    "Modulation", "64QAM", ...
    "NumLayers", double(layers), ...
    "RateMatchedBitCount", double(E));
end

function localAssertThrows(fn, expected)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(expected), ...
        "Expected %s, got %s.", expected, ME.identifier);
    return;
end
error("testPDSCHTwoCodewordHARQContext:ExpectedErrorMissing", ...
    "Expected typed error %s.", expected);
end
