function ok = testPartialCampaignReportHonesty()
%TESTPARTIALCAMPAIGNREPORTHONESTY Partial campaigns must report skipped modules honestly.

setup6GRSimToolkit("Verbose", false);

tmp = fullfile(pwd,'results','sls','partial_campaign_report_honesty', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(tmp);
fprintf('PARTIAL_REPORT_EVIDENCE_ROOT=%s\n',tmp);
[cfg,nSlots] = e2eReceivedAccessConfig(tmp,2,"xr");
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;

rep = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmp, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", nSlots*sixgr.time.slotDurationSec(cfg), ...
    "E2EMaxSlots", nSlots, ...
    "E2EUECount", 2, ...
    "E2ETrafficModel", "xr", ...
    "E2EAirModel", "truth", ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", true, ...
    "GenerateCampaignPlots", false, ...
    "E2EStrictValidation", true, ...
    "E2ETruthFastAWGNPath", false, ...
    "E2ETruthMaxSlots", nSlots, ...
    "LinkSNR_dB", 30);

assert(rep.Ok, "E2E-only run used for report-honesty regression should pass.");
assert(height(rep.E2E.ReceivedAccessBindings)==2 && ...
    numel(unique(rep.E2E.SchedulerTraceTable.UE))==2, ...
    'Report honesty must be checked with actual per-UE access and data.');
assert(all(ismember(["DL","UL"],upper(string(rep.E2E.SchedulerTraceTable.Direction)))), ...
    'Report honesty must retain the original bidirectional traffic coverage.');

runFolder = char(string(rep.RunFolder));
layout = sixgr.report.resultLayout(runFolder);
audit = readtable(layout.CategoryAuditCSV, ...
    "VariableNamingRule", "preserve", ...
    "Delimiter", ",", ...
    "ReadVariableNames", true, ...
    "FileType", "text");
evidence = lower(string(audit.Evidence));
status = lower(string(audit.Status));
linkOrSystem = contains(evidence, "air_interface/") | contains(evidence, "air_interface\\") | ...
    contains(evidence, "system/") | contains(evidence, "system\\");
claimed = status == "implemented" | status == "approximated";
assert(~any(linkOrSystem & claimed), ...
    "E2E-only category audit must not claim implemented/approximated link or system evidence.");

txt = lower(fileread(layout.CampaignReportMD));
assert(contains(txt, "- link run: `skipped`"), ...
    "Markdown report must mark link run as skipped for E2E-only runs.");
assert(contains(txt, "- detailed lls: `skipped`"), ...
    "Markdown report must mark detailed LLS as skipped for E2E-only runs.");
assert(contains(txt, "- system mobility: `skipped`"), ...
    "Markdown report must mark system mobility as skipped for E2E-only runs.");
assert(~contains(txt, "link run folder:"), ...
    "Markdown report must not print a link folder line for skipped runs.");
assert(~contains(txt, "system folder:"), ...
    "Markdown report must not print a system folder line for skipped runs.");

ok = true;
end
