function ok = testVisualComponentLineageStatus()
%TESTVISUALCOMPONENTLINEAGESTATUS Incomplete lineage is not a rendered image.

setup6GRSimToolkit("Verbose", false);
root = string(tempname);
cleanupObj = onCleanup(@()localCleanup(root)); %#ok<NASGU>
mkdir(fullfile(root, "reports", "csv"));

lineage = table( ...
    "distance_vs_sinr", ...
    "reports/image/distance_vs_sinr.png", ...
    "air_interface/csv/distance_vs_sinr.csv", ...
    false, false, 0, "real_lls_measured_sinr_analytics", "incomplete", ...
    'VariableNames', ["PlotId","ImagePath","SourceCSV","ImageExists", ...
    "SourceExists","SourceRowCount","TruthStatus","LineageStatus"]);
sixgr.util.csvWriteTable(fullfile(root, "reports", "csv", ...
    "measurement_sinr_plot_lineage.csv"), lineage);

integrity = sixgr.visual.verifyVisualArtifacts(root, table());
assert(height(integrity) == 1, ...
    "Incomplete component lineage must remain visible as one non-rendered audit row.");
assert(logical(integrity.IntegrityOk(1)) && ...
    string(integrity.PlotRenderStatus(1)) == "not_rendered" && ...
    strlength(string(integrity.FailureCode(1))) == 0, ...
    "An explicitly incomplete, absent plot must not be mislabeled as a broken rendered image.");

mkdir(fullfile(root, "reports", "image"));
imwrite(uint8(zeros(8, 8, 3)), ...
    fullfile(root, "reports", "image", "distance_vs_sinr.png"));
stale = sixgr.visual.verifyVisualArtifacts(root, table());
assert(any(~logical(stale.IntegrityOk) & ...
    string(stale.FailureCode) == "stale_suppressed_normal_artifact"), ...
    "Incomplete component lineage must fail if stale image bytes are present.");
ok = true;
end

function localCleanup(pathValue)
if exist(pathValue, "dir") == 7
    rmdir(pathValue, "s");
end
end
