function tests = testWaveformLiveStageResolution
tests = functiontests(localfunctions);
end

function testStageRequiresCompletedRows(testCase)
verifyEqual(testCase, ...
    sixgr.truth.resolveWaveformLiveStage(0, 0, [0 0 0 0]), ...
    "control_access_pending");
verifyEqual(testCase, ...
    sixgr.truth.resolveWaveformLiveStage(0, 0, [1 0 0 0]), ...
    "control_gating_streaming");
verifyEqual(testCase, ...
    sixgr.truth.resolveWaveformLiveStage(1, 0, [1 0 0 0]), ...
    "dl_raw_trials_streaming");
verifyEqual(testCase, ...
    sixgr.truth.resolveWaveformLiveStage(0, 1, [1 0 0 0]), ...
    "ul_raw_trials_streaming");
verifyEqual(testCase, ...
    sixgr.truth.resolveWaveformLiveStage(1, 1, [1 1 1 1]), ...
    "dl_ul_raw_trials_streaming");
end

function testInvalidCountsFailClosed(testCase)
verifyError(testCase, ...
    @() sixgr.truth.resolveWaveformLiveStage(NaN, 0, 0), ...
    "sixgr:truth:InvalidLiveTrialRowCount");
verifyError(testCase, ...
    @() sixgr.truth.resolveWaveformLiveStage(0, 0, [0 -1]), ...
    "sixgr:truth:InvalidLiveControlAttemptCounts");
end
