function ok=testPacketLedgerRuntimePublication()
% Public live/final writers must reconcile late feedback without another RX.
% Outcomes below are declared MAC fixtures, not measured waveform results.
setup6GRSimToolkit('Verbose',false);
root=fullfile(pwd,'logs','lls_repairs', ...
    ['packet_runtime_publication_' char(datetime('now','Format','yyyyMMdd_HHmmss_SSS'))]);
s=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_pdcch_shared_queue_fixture.yaml');
cfg=sixgr.lls6g.buildInternalConfig(s,root);
multi=struct('Enabled',true,'NumUsers',1,'RNTIStart',1,'ExecutionModel','slot_coupled_truth');
state=sixgr.truth.CoupledTruthRuntime.initialize(cfg,root,multi,struct(),4);
state.CurrentSlot=4; state.CurrentFrame=1; state.CurrentCanonicalSlot=4;
state.CurrentSweepPointIndex=1; state.CurrentSNR_dB=20;
state.ProtocolWaveformEnabled=false;
P=table(); S=table(); H=table();
for direction=["DL","UL"]
    h=sixgr.l2.mac.HARQEntity(struct(),'Direction',direction,'NumProcesses',1,'MaxRetx',0);
    a=h.allocate(321,1,100);
    layout=sixgr.phy.phycode.resolveCodingLayout('Direction',direction, ...
        'TransportBlockSize',800,'TargetCodeRate',.3,'RV',a.HARQ.RV, ...
        'Modulation','QPSK','NumLayers',1,'RateMatchedBitCount',2748);
    g=struct('RNTI',321,'UEIndex',1,'ServingCell',1,'Slot',1,'Frame',1, ...
        'HARQ',a.HARQ,'TBSBits',800,'Direction',direction,'Modulation','QPSK', ...
        'NumLayers',1,'TargetCodeRate',.3,'CodingLayout',layout, ...
        'TBId',direction+"-TB",'TransportBlockId',direction+"-TB", ...
        'GrantContextId',direction+"-attempt",'PHYGrantContextId',direction+"-attempt");
    h.onTx(321,0,uint8(mod((1:800)',2)),g,1);
    assert(h.onFeedback(321,0,"NACK",'SourceSlot',1,'FeedbackSlot',4));
    state.(direction+"Harq")=h;
    p=struct('Direction',direction,'UEIndex',1,'RNTI',321,'PacketId',"packet", ...
        'ApplicationPacketId',"app",'OfferedBits',1600,'ScheduledBits',800, ...
        'RemainingBits',800,'DeliveredBits',0,'DeliverySuccess',false,'HARQAttemptCount',0, ...
        'ReservedInFlightBits',800,'HARQReleasedUndeliveredBits',0, ...
        'PacketizationSource',"declared_MAC_fixture_not_waveform_result");
    d=struct('Direction',direction,'UEIndex',1,'RNTI',321,'PacketId',"packet", ...
        'ApplicationPacketId',"app",'TransportBlockId',g.TBId,'HARQProcessId',0, ...
        'NDIEpoch',a.HARQ.NDIEpoch,'ScheduleSlot',1,'SegmentIndex',1,'PayloadBits',800, ...
        'DeliverySuccess',false,'HARQAttemptCount',0, ...
        'DeliveryEvidenceMode',"CRC_CONFIRMED_PACKET_MAPPING");
    r=struct('Direction',direction,'UEIndex',1,'RNTI',321,'HarqID',0, ...
        'NDIEpoch',a.HARQ.NDIEpoch,'TBId',g.TBId,'PHYGrantContextId',g.PHYGrantContextId, ...
        'Slot',1,'Frame',1,'CombinedDecodeOK',false,'IsRetransmission',false, ...
        'MeasuredSINR_dB',NaN,'WidebandCQI',NaN,'CQIDerivedMCS',NaN, ...
        'Source',"declared_MAC_fixture_not_waveform_result");
    P=[P;struct2table(p)]; S=[S;struct2table(d)]; H=[H;struct2table(r)]; %#ok<AGROW>
end
state.PacketDeliveryLedgerTable=P; state.PacketSDULedgerTable=S; state.HARQTimelineTable=H;
for mode=["live","final"]
    out=fullfile(root,mode);
    if mode=="live"
        current=sixgr.truth.CoupledTruthRuntime.writeLiveStateTables(state,out);
    else
        current=sixgr.truth.CoupledTruthRuntime.writeTables(state,out);
    end
    path=fullfile(out,'packet_flow','csv','live_application_packet_delivery_ledger.csv');
    assert(isfile(path),'test:PacketLedgerNotPublished','The public %s writer omitted packet evidence.',mode);
    actual=sixgr.util.csvReadTable(path);
    assert(all(actual.ReservedInFlightBits==0 & actual.HARQReleasedUndeliveredBits==800 & ...
        actual.HARQRetryLimitDroppedBits==800 & actual.UnscheduledBits==800 & ...
        actual.HARQAttemptCount==1 & actual.CompletedApplicationBits==0 & actual.BitConservationErrorBits==0), ...
        'test:StalePacketPublication','The public writer retained pre-feedback packet counters.');
    assert(all(current.PacketDeliveryLedgerTable.HARQReleasedUndeliveredBits==800));
    sdu=sixgr.util.csvReadTable(fullfile(out,'packet_flow','csv','live_packet_sdu_delivery_ledger.csv'));
    assert(all(sdu.PacketBitState=="HARQReleasedUndeliveredBits" & ...
        sdu.HARQAttemptCount==1 & sdu.ApplicationRangeStartBit==0 & sdu.ApplicationRangeEndBitExclusive==800));
    attemptsPath=fullfile(out,'harq','csv','runtime_harq_process_timeline.csv');
    assert(isfile(attemptsPath),'test:PacketAttemptSourceNotPublished', ...
        'The public %s packet snapshot must retain its actual attempt-count source.',mode);
    attempts=sixgr.util.csvReadTable(attemptsPath);
    assert(isequal(string(attempts.PHYGrantContextId),string(H.PHYGrantContextId)) && ...
        isequal(double(attempts.CombinedDecodeOK),double(H.CombinedDecodeOK)) && ...
        isequal(string(attempts.Source),string(H.Source)));
end
% The shared publisher owns the journal even without an application ledger.
% Empty/missing evidence must not acquire reconstructed physical attempts.
out=fullfile(root,'attempts_only');
[~,paths]=sixgr.truth.publishPacketDeliveryLedgers(struct('HARQTimelineTable',H),out);
assert(isfield(paths,'HARQ') && ~isfield(paths,'Application'));
attempts=sixgr.util.csvReadTable(paths.HARQ);
assert(height(attempts)==height(H) && isequal(string(attempts.Source),string(H.Source)));
[~,paths]=sixgr.truth.publishPacketDeliveryLedgers( ...
    struct('HARQTimelineTable',H([],:)),fullfile(root,'empty_attempts'));
attempts=sixgr.util.csvReadTable(paths.HARQ);
assert(height(attempts)==0 && ismember('PHYGrantContextId',attempts.Properties.VariableNames));
out=fullfile(root,'missing_attempts');
[~,paths]=sixgr.truth.publishPacketDeliveryLedgers(rmfield(state,'HARQTimelineTable'),out);
assert(~isfield(paths,'HARQ') && ~isfile(fullfile(out,'harq','csv','runtime_harq_process_timeline.csv')));
fprintf('PACKET_RUNTIME_PUBLICATION_PASS folder=%s declared_MAC_only=1\n',root);
ok=true;
end
