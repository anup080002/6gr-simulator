function ok = testLLSMobile2UEScenarioYamlWiring()
%TESTLLSMOBILE2UESCENARIOYAMLWIRING Verify the mobile 2UE study YAML is present and runtime-wired.

setup6GRSimToolkit("Verbose", false);

scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "lls_mobile_2ue_100kmh_1sector_full_capture.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
resolved = scfg.toStruct();

requiredSections = { ...
    'waveform', ...
    'deployment_topology', ...
    'channels', ...
    'mimo', ...
    'modulation', ...
    'coding', ...
    'reference_signals', ...
    'csi_acquisition_and_reporting', ...
    'link_adaptation', ...
    'harq', ...
    'pucch_resources', ...
    'random_access', ...
    'sib1_and_initial_access', ...
    'random_access_evidence', ...
    'scheduler', ...
    'power_control', ...
    'impairments', ...
    'decoder_output_capture', ...
    'dut_reference_validation', ...
    'channel_rf_configured_vs_applied', ...
    'air_interface', ...
    'traffic', ...
    'energy_efficiency', ...
    'analytics'};
for idx = 1:numel(requiredSections)
    assert(isfield(resolved, requiredSections{idx}), ...
        "Resolved mobile study config must contain section '%s'.", requiredSections{idx});
end

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() localCleanupTempFolder(tmp)); %#ok<NASGU>
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));

assert(logical(sixgr.util.structGet(cfg, "phy.waveform.windowingEnabled", false)), ...
    "waveform.windowing_enabled must wire into phy.waveform.windowingEnabled.");
assert(abs(double(sixgr.util.structGet(cfg, "phy.waveform.windowingPercent", NaN)) - 0.025) < 1e-12, ...
    "waveform.windowing_percent must wire into the OFDM windowing runtime config.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.pdsch.mcsTable", ""))), "qam256_table2"), ...
    "modulation.dl_mcs_table must wire into phy.pdsch.mcsTable.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.pusch.mcsTable", ""))), "qam256_table2"), ...
    "modulation.ul_mcs_table must wire into phy.pusch.mcsTable.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.csi.cqiTable", ""))), "table2"), ...
    "link_adaptation.cqi_table must wire into phy.csi.cqiTable.");
assert(logical(sixgr.util.structGet(cfg, "phy.linkAdaptation.outerLoopFlag", false)), ...
    "link_adaptation.outer_loop_flag must enable runtime ACK/NACK OLLA for the mobile waveform scenario.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.linkAdaptation.deltaMCSPolicy", ""))), "ack_nack_olla"), ...
    "link_adaptation.delta_mcs_policy must wire into the scheduler OLLA policy.");
assert(abs(double(sixgr.util.structGet(cfg, "phy.linkAdaptation.ollaStepUp", NaN)) - 0.10) < 1e-12 && ...
    abs(double(sixgr.util.structGet(cfg, "phy.linkAdaptation.ollaStepDown", NaN)) - 0.90) < 1e-12, ...
    "link_adaptation.olla_step_* values must wire into scheduler ACK/NACK OLLA.");
assert(abs(double(sixgr.util.structGet(cfg, "phy.pdsch.targetBLER", NaN)) - 0.10) < 1e-12 && ...
    abs(double(sixgr.util.structGet(cfg, "phy.pusch.targetBLER", NaN)) - 0.10) < 1e-12, ...
    "link_adaptation.target_bler_dl/ul must wire into the DL and UL PHY target BLER configuration.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.csi.channelStateInformationMode", ""))), "PMI+CQI+RI"), ...
    "csi_acquisition_and_reporting.channel_state_information_mode must wire into phy.csi.channelStateInformationMode.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.csi.codebookType", ""))), "type1"), ...
    "mimo.codebook_type must wire into phy.csi.codebookType.");
assert(double(sixgr.util.structGet(cfg, "phy.carrier.NSizeGrid", NaN)) == 273, ...
    "frequency.n_size_grid must wire into phy.carrier.NSizeGrid.");
assert(double(sixgr.util.structGet(cfg, "phy.numerology.activeGridNumRBs", NaN)) == 273, ...
    "frequency.n_size_grid must wire into the active runtime RB grid.");
assert(isequal(double(sixgr.util.structGet(cfg, "phy.harq.rvSequence", zeros(0, 1))).', [0 2 3 1]), ...
    "harq.rv_sequence must wire into phy.harq.rvSequence.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "system.scheduler.type", ""))), "PF"), ...
    "scheduler.type must resolve into system.scheduler.type.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "mac.scheduler.type", ""))), "PF"), ...
    "scheduler.type must resolve into mac.scheduler.type.");
assert(double(sixgr.util.structGet(cfg, "phy.pdsch.maxLayers", NaN)) == 2 && ...
    double(sixgr.util.structGet(cfg, "phy.pdsch.numLayers", NaN)) == 2, ...
    "mimo.max_dl_layers must cap the DL runtime layer configuration.");
assert(double(sixgr.util.structGet(cfg, "phy.pusch.maxLayers", NaN)) == 2 && ...
    double(sixgr.util.structGet(cfg, "phy.pusch.numLayers", NaN)) == 2, ...
    "mimo.max_ul_layers must cap the UL runtime layer configuration.");
assert(double(sixgr.util.structGet(cfg, "phy.pdsch.dmrs.additionalPositions", NaN)) == 2 && ...
    double(sixgr.util.structGet(cfg, "phy.pusch.dmrs.additionalPositions", NaN)) == 2, ...
    "reference_signals.*_dmrs_additional_positions must wire into DL and UL runtime DMRS configs.");
[carrierForDMRS, ~] = sixgr.phy.grid.makeCarrier(cfg);
[~, ~, pdschForDMRS] = sixgr.phy.grid.allocREsPDSCH(carrierForDMRS, cfg);
[~, ~, puschForDMRS] = sixgr.phy.grid.allocREsPUSCH(carrierForDMRS, cfg);
assert(double(pdschForDMRS.DMRS.DMRSAdditionalPosition) == 2 && ...
    double(puschForDMRS.DMRS.DMRSAdditionalPosition) == 2, ...
    "DL/UL allocation objects must honor configured DMRSAdditionalPosition for measured tracking.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.pusch.uciMultiplexingMode", ""))), "harq_ack_on_pusch_when_pucch_collides"), ...
    "pucch_resources.overlap_policy.uci_on_pusch_enabled=true must enable HARQ-ACK UCI multiplexing on colliding PUSCH grants.");
assert(logical(sixgr.util.structGet(cfg, "phy.pusch.powerControl.enabled", false)), ...
    "power_control.ul_open_loop_enable must enable UL runtime power control.");
assert(abs(double(sixgr.util.structGet(cfg, "phy.pusch.powerControl.p0PUSCH_dBm", NaN)) + 80) < 1e-12, ...
    "power_control.p0_pusch_dBm must wire into phy.pusch.powerControl.p0PUSCH_dBm.");
assert(abs(double(sixgr.util.structGet(cfg, "phy.pusch.powerControl.alpha", NaN)) - 0.8) < 1e-12, ...
    "power_control.alpha_pusch must wire into phy.pusch.powerControl.alpha.");
assert(abs(double(sixgr.util.structGet(cfg, "phy.pusch.powerControl.pcmax_dBm", NaN)) - 23) < 1e-12, ...
    "power_control.pcmax_dBm must wire into phy.pusch.powerControl.pcmax_dBm.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "prach_lls.DetectionThresholdMode", ""))), "auto"), ...
    "random_access.detection_threshold_mode must wire into the PRACH runtime config.");
assert(logical(sixgr.util.structGet(cfg, "outputs.rawIQCaptureEnabled", false)), ...
    "run_control.raw_iq_capture_enable must wire into the runtime output config.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.pucch.format", ""))), "2"), ...
    "pucch_resources must preserve the requested format-2 runtime default.");
assert(isequal(double(sixgr.util.structGet(cfg, "phy.pucch.PRBSet", NaN)), [2 3 4 5]), ...
    "pucch_resources.resources must wire the default PRB set into cfg.phy.pucch.PRBSet.");
assert(isequal(double(sixgr.util.structGet(cfg, "phy.pucch.SymbolAllocation", NaN)), [8 2]), ...
    "pucch_resources.resources must wire the default symbol allocation into cfg.phy.pucch.SymbolAllocation.");
assert(double(sixgr.util.structGet(cfg, "mac.harq.k1", NaN)) == 4, ...
    "pucch_resources.harq_ack.k1_slots must override the runtime HARQ feedback timing.");
assert(logical(sixgr.util.structGet(cfg, "phy.sib1.enable", false)), ...
    "sib1_and_initial_access must enable the strict SIB1 waveform path.");
objectives = string(sixgr.util.structGet(cfg, "validation.objectives", cell(0, 1)));
assert(any(objectives == "cell_search_mib_sib1") && ...
    any(objectives == "random_access_four_step") && ...
    any(objectives == "channel_rf_strict_validation"), ...
    "The added strict-audit sections must wire their runtime truth objectives into cfg.validation.objectives.");
assert(logical(sixgr.util.structGet(cfg, "phy.impairments.phaseNoiseEnabled", false)), ...
    "impairments.phase_noise_enabled must wire into phy.impairments.phaseNoiseEnabled.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "rf.phaseNoise.model", ""))), "Lorentzian") && ...
    abs(double(sixgr.util.structGet(cfg, "rf.phaseNoise.L0_dBcHz", NaN)) + 94.0) < 1e-12 && ...
    abs(double(sixgr.util.structGet(cfg, "rf.phaseNoise.f3dB_Hz", NaN)) - 10000) < 1e-12 && ...
    abs(double(sixgr.util.structGet(cfg, "rf.phaseNoise.floor_dBcHz", NaN)) + 140.0) < 1e-12, ...
    "impairments.phase_noise_* mask fields must wire into the runtime RF phase-noise model.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "phy.impairments.cfoEstimationMethod", ""))), "dmrs_two_symbol"), ...
    "impairments.cfo_estimation_method must wire into the receiver tracking runtime config.");
assert(logical(sixgr.util.structGet(cfg, "phy.rx.cfoCorrectionEnabled", false)) && ...
    logical(sixgr.util.structGet(cfg, "phy.impairments.cfoCorrectionEnabled", false)), ...
    "impairments.cfo_correction_enable must wire into the receiver CFO correction runtime config.");
assert(logical(sixgr.util.structGet(cfg, "phy.rx.iqImbalanceCorrectionEnabled", false)) && ...
    logical(sixgr.util.structGet(cfg, "phy.impairments.iqImbalanceCorrectionEnabled", false)), ...
    "impairments.iq_imbalance_correction_enable must wire into the receiver IQ correction runtime config.");
assert(logical(sixgr.util.structGet(cfg, "perf.exportTimeProfile", false)), ...
    "analytics.export_time_profile must wire into perf.exportTimeProfile.");
assert(abs(double(scfg.get("energy_efficiency.ai_compute_energy_per_flop_score")) - 1e-6) < 1e-12, ...
    "energy_efficiency.ai_compute_energy_per_flop_score must remain available on the resolved ScenarioConfig for runSingle.");
assert(strcmpi(char(string(scfg.get("channels.o2i_model", ""))), "low"), ...
    "channels.o2i_loss_model aliases must materialize the strict runtime channels.o2i_model token.");
assert(strcmpi(char(string(sixgr.util.structGet(cfg, "channel.o2i.model", ""))), "low"), ...
    "channels.o2i_loss_model must wire into cfg.channel.o2i.model using the strict low/high/custom/none enum.");
assert(~logical(sixgr.util.structGet(cfg, "run.useMex", true)), ...
    "Strict mobile coupled-waveform scenarios must disable exact-MEX acceleration by default.");
assert(~logical(sixgr.util.structGet(cfg, "phy.ldpc.useMexBatchDecode", true)), ...
    "Strict mobile coupled-waveform scenarios must disable LDPC batch-decode MEX acceleration by default.");
assert(strcmpi(char(string(resolved.channels.profile)), "CDL-C") && logical(resolved.channels.los_enabled), ...
    "The mobile study channel profile must resolve to CDL-C with LOS enabled.");
assert(strcmpi(char(string(resolved.mimo.reciprocity_mode)), "TDD"), ...
    "The mobile study reciprocity mode must resolve to TDD.");
assert(double(resolved.reference_signals.pusch_dmrs_ports) == 2 && ...
    double(resolved.reference_signals.srs_ports) == 2, ...
    "The mobile study UL reference-signal ports must stay aligned with the 2-layer UL configuration.");
assert(isequal(double(sixgr.util.structGet(cfg, "phy.srs.slotWithinPeriod1Based", zeros(0, 1))).', [5 10 15 20]), ...
    "reference_signals.srs_slot_within_period must wire into coupled-runtime SRS occasion gating.");
assert(double(sixgr.util.structGet(cfg, "phy.ssb.period_slots", NaN)) == 40 && ...
    double(sixgr.util.structGet(cfg, "phy.pbch.period_slots", NaN)) == 40, ...
    "reference_signals.ssb_periodicity_ms must wire into coupled-runtime SSB/PBCH acquisition cadence.");
assert(double(sixgr.util.structGet(cfg, "phy.trs.period_slots", NaN)) == 20, ...
    "reference_signals.trs_periodicity_ms must wire into coupled-runtime TRS tracking cadence.");
assert(double(sixgr.util.structGet(cfg, "run.controlGating.trsMaxAgeSlots", NaN)) == 20, ...
    "control_gating.trs_max_age_slots must preserve TRS freshness through the configured TRS periodicity.");
assert(double(sixgr.util.structGet(cfg, "phy.prach.period_slots", NaN)) == 10 && ...
    isequal(double(sixgr.util.structGet(cfg, "phy.prach.validSlots1Based", zeros(0, 1))), [5 15]), ...
    "random_access configuration_index must materialize PRACH occasions and a coupled-runtime PRACH cadence.");
assert(double(sixgr.util.structGet(cfg, "run.controlGating.srsMaxAgeSlots", NaN)) == 5, ...
    "control_gating.srs_max_age_slots must preserve SRS freshness through the configured K2 UL scheduling path.");
assert(double(sixgr.util.structGet(cfg, "phy.srs.maxUEsPerSlot", NaN)) == 2 && ...
    strcmpi(char(string(sixgr.util.structGet(cfg, "phy.srs.schedulingPolicy", ""))), "multiplex_due_users"), ...
    "reference_signals.srs_max_ues_per_slot/srs_scheduling_policy must allow both mobile UEs to refresh UL CSI on configured SRS occasions.");
layout = sixgr.scenario.generateLayout(cfg);
assert(strcmpi(char(string(layout.layoutType)), "rect_grid"), ...
    "The mobile 2UE scenario deployment must remain executable through the rect_grid layout token.");
assert(~logical(layout.wraparoundEnabled), ...
    "The mobile 2UE single-sector scenario must honor deployment_topology.wraparound_enabled=false.");
assert(double(layout.nSites) == 1 && double(layout.nTRxP) == 1, ...
    "The mobile 2UE single-sector scenario must generate one site and one TRxP.");
assert(all(abs(double(layout.bs.pos_m(1, 1:2))) < 1e-9), ...
    "The mobile 2UE single-site rect-grid TRP must be centered at the local origin.");
ue = sixgr.scenario.dropUEs(cfg, layout);
initialDistances_m = hypot(double(ue.pos_m(:,1)) - double(layout.bs.pos_m(1,1)), ...
    double(ue.pos_m(:,2)) - double(layout.bs.pos_m(1,2)));
assert(all(abs(initialDistances_m - [50; 500]) < 1e-9), ...
    "Configured mobile 2UE paths must enter large-scale pathloss at the requested 50 m and 500 m BS distances.");
assert(all(double(ue.max_ue_bs_distance_m) == 500), ...
    "deployment_topology.max_ue_distance_from_bs_m must wire into the UE drop distance bounds.");
ctx = sixgr.core.SimContext(cfg, "RunFolder", fullfile(tmp, "run"));
ctx.Logger.EchoToConsole = false;
out = sixgr.system.SystemLevelRunner.run(ctx, struct( ...
    "PHYBackend", "waveform", ...
    "DetailedTrace", true, ...
    "NumTTI", 4, ...
    "SimDuration_s", 4 * 0.5e-3));
ctx.Logger.close();
assert(logical(out.Ok), ...
    "The mobile 2UE scenario must complete a 4-slot waveform-backed system run. Errors: %s", ...
    strjoin(cellstr(out.Errors), " | "));
grantT = sixgr.util.structGet(out, "Details.SchedulerGrants", table());
assert(istable(grantT), ...
    "SystemLevelRunner must export the scheduler grant trace for the mobile 2UE smoke run.");
grantVars = string(grantT.Properties.VariableNames);
assert(all(ismember(["AMCMode","OuterLoopEnabled","OuterLoopApplied","OLLADeltaMCS","OLLAUpdateCount","OLLAState"], grantVars)), ...
    "SystemLevelRunner scheduler-grant CSV must preserve runtime AMC/OLLA evidence columns.");
slot4UL = grantT(double(grantT.TTI) == 4 & string(grantT.Direction) == "UL", :);
assert(isempty(slot4UL), ...
    "The one-symbol UL tail in the canonical special slot must not emit executable UL data grants.");

ok = true;
end

function localCleanupTempFolder(tmp)
runLog = fullfile(tmp, "run", "logs", "run.log");
if exist(runLog, "file") == 2
    fclose("all");
end
if isfolder(tmp)
    rmdir(tmp, "s");
end
end
