function ok = testPostEqSINR()
%TESTPOSTEQSINR Validate post-equalization SINR and CQI provenance guards.

setup6GRSimToolkit("Verbose", false);

H = ones(32, 1, 1);
[sinr_dB, perRE, info] = sixgr.phy.rx.computePostEqSINR(H, 1, "Method", "mmse");
assert(abs(double(sinr_dB)) < 1e-9, "Unit SISO channel with nVar=1 must produce 0 dB post-eq SINR.");
assert(all(isfinite(perRE(:))), "Per-RE SINR must be finite for valid SISO input.");
assert(strcmp(string(info.ValueStatus), "OK"), "PostEqSINR info must report OK for valid input.");
assert(strcmp(string(info.ValueRole), "measured_post_equalization_scheduling_input"), ...
    "PostEqSINR must declare scheduler-eligible measured post-eq provenance.");

H2 = repmat(reshape(eye(2), 1, 2, 2), 16, 1, 1);
[sinr2_dB, perRE2, info2] = sixgr.phy.rx.computePostEqSINR(H2, 0.1, "Method", "mmse", "Layers", 2);
assert(isfinite(double(sinr2_dB)) && size(perRE2, 2) == 2, ...
    "2x2 post-eq SINR must return finite wideband and two layer columns.");
assert(all(isfinite(double(info2.PerLayerSINR_dB))), "2x2 post-eq SINR must expose finite per-layer means.");

Rint = 10 * eye(2);
[sinrCov_dB, ~, infoCov] = sixgr.phy.rx.computePostEqSINR(H2, 0.1, "Method", "mmse", "Rint", Rint, "Layers", 2);
assert(isfinite(double(sinrCov_dB)) && double(sinrCov_dB) < double(sinr2_dB), ...
    "MMSE post-eq SINR must account for observed DMRS residual impairment covariance.");
assert(logical(infoCov.ImpairmentCovarianceUsed) && strcmp(string(infoCov.ImpairmentCovarianceSource), "dmrs_residual_impairment_covariance"), ...
    "PostEqSINR metadata must disclose observed residual covariance usage.");

[sinrIRC_dB, ~, infoIRC] = sixgr.phy.rx.computePostEqSINR(H2, 0.1, "Method", "irc", "Rint", Rint, "Layers", 2);
assert(isfinite(double(sinrIRC_dB)) && strcmpi(string(infoIRC.Method), "irc") && ...
    logical(infoIRC.ImpairmentCovarianceUsed), ...
    "IRC post-eq SINR must remain on the IRC path and disclose covariance usage when Rint is supplied.");
rxSym = repmat([1 -1], 16, 1);
[~, csiIRC, detectIRC] = sixgr.phy.rx.mimoDetect(rxSym, H2, 0.1, "Algorithm", "IRC", "Rint", [0.5 0.2; 0.2 2.0]);
assert(strcmpi(string(detectIRC.AlgorithmUsed), "IRC") && strcmpi(string(detectIRC.EngineUsed), "manualIRC") && ...
    all(isfinite(double(csiIRC(:)))), ...
    "MIMO detector must use the covariance-backed manual IRC engine when Rint is available.");
[~, ~, detectNoCov] = sixgr.phy.rx.mimoDetect(rxSym, H2, 0.1, "Algorithm", "IRC");
assert(strcmpi(string(detectNoCov.AlgorithmUsed), "MMSE") && contains(string(detectNoCov.EngineUsed), "IRC_fallback_MMSE"), ...
    "MIMO detector must disclose MMSE downgrade when IRC covariance is unavailable.");

[badSINR, ~, badInfo] = sixgr.phy.rx.computePostEqSINR(H, NaN);
assert(~isfinite(double(badSINR)) && strcmp(string(badInfo.ValueStatus), "unavailable"), ...
    "Invalid noise variance must fail closed instead of fabricating post-eq SINR.");

[limitedSINR, limitedPerRE, limitedInfo] = sixgr.phy.rx.computePostEqSINR(H, 1e-12, ...
    "Method", "mmse", "MaxTrustedSINR_dB", 45);
assert(abs(double(limitedSINR) - 45) < 1e-9 && ...
    strcmp(string(limitedInfo.ValueStatus), "OK_dynamic_range_limited") && ...
    double(limitedInfo.RawSINR_dB) > 100 && all(double(limitedPerRE(:)) <= 45 + 1e-9), ...
    "Post-eq SINR must preserve raw metadata but cap scheduler-facing dynamic range when max trusted SINR is configured.");

[nVarEff, nVarInfo] = sixgr.phy.rx.postEqualizationNoiseVariance(1e-9, ...
    "PostEqSINRPerRE_dB", repmat(20, 16, 1));
assert(abs(double(nVarEff) - 1e-2) < 1e-12 && strcmp(string(nVarInfo.Source), "post_equalization_sinr_per_re"), ...
    "Decoder noise variance must be derived in the post-equalization unit-symbol domain.");

[nVarCSI, csiInfo] = sixgr.phy.rx.postEqualizationNoiseVariance(1e-9, ...
    "CSI", repmat(100 / 101, 16, 1));
assert(abs(double(nVarCSI) - 1e-2) < 1e-9 && strcmp(string(csiInfo.Source), "equalizer_csi_weights"), ...
    "Bounded MMSE CSI reliability weights must map to equivalent post-eq noise variance.");

cqiLegacy = arrayfun(@(x) sixgr.phy.dl.mapSINRToCQI(x, "table1"), [-5.2 -3.5 0.5 10.5]);
assert(isequal(double(cqiLegacy(:)).', [1 2 4 9]), ...
    "Legacy mapSINRToCQI must use the non-uniform table thresholds, not a 2 dB ladder.");

cfg = struct();
cfg.phy.csi.cqiTable = "table1";
accepted = sixgr.link.resolveWidebandCQI(struct( ...
    "WidebandSINR_dB", 12, ...
    "SINRSource", "post_equalization_sinr_from_equalizer_channel_estimate", ...
    "SINRValueRole", "measured_post_equalization_scheduling_input", ...
    "SINRValueStatus", "OK"), cfg, "DL");
assert(logical(accepted.SINRInputAccepted) && isfinite(double(accepted.WidebandCQI)), ...
    "CQI resolver must accept scheduler-eligible post-eq SINR.");

rejected = sixgr.link.resolveWidebandCQI(struct( ...
    "WidebandSINR_dB", 30, ...
    "SINRSource", "receiver_hest_reference_signal_measurement", ...
    "SINRValueRole", "estimated", ...
    "SINRValueStatus", "OK"), cfg, "DL");
assert(~logical(rejected.SINRInputAccepted) && ~isfinite(double(rejected.WidebandCQI)), ...
    "CQI resolver must reject ReceiverHest/pilot SINR as a scheduling input.");

evmRejected = sixgr.link.resolveWidebandCQI(struct( ...
    "WidebandSINR_dB", 25, ...
    "SINRSource", "evm_proxy_not_true_post_equalization_sinr", ...
    "SINRValueRole", "diagnostic_evm_proxy_not_scheduling_input", ...
    "SINRValueStatus", "OK"), cfg, "DL");
assert(~logical(evmRejected.SINRInputAccepted) && ~isfinite(double(evmRejected.WidebandCQI)), ...
    "CQI resolver must reject EVM proxy SINR as a scheduling input.");

rng(42, "twister");
targetEVM = 0.1;
qpsk = exp(1j * (pi/4 + (0:3).' * pi/2));
refSym = repmat(qpsk, 1024, 1);
noise = targetEVM / sqrt(2) * (randn(size(refSym)) + 1j * randn(size(refSym)));
cfgEVM = struct();
cfgEVM.phy.pdsch.modulation = "QPSK";
[evmMetrics, ~] = sixgr.link.deriveModulationTrackingMetrics( ...
    struct("PDSCHSymbols", refSym), ...
    struct("EqualizedSymbols", refSym + noise), cfgEVM, "DL");
assert(strcmpi(string(evmMetrics.EVMStatus), "OK") && ...
    abs(double(evmMetrics.EVM_rms) - targetEVM) < 0.015, ...
    "EVM must be calibrated as RMS error against a unit-power reference constellation.");
[primarySINR, evmMeta] = sixgr.link.deriveDecoderTruthProxySINR(evmMetrics);
assert(~isfinite(double(primarySINR)) && isfinite(double(evmMeta.DiagnosticEVMProxySINR_dB)) && ...
    abs(double(evmMeta.DiagnosticEVMProxySINR_dB) + 20 * log10(double(evmMetrics.EVM_rms))) < 1e-9 && ...
    strcmpi(string(evmMeta.ValueRole), "unavailable") && ...
    strcmpi(string(evmMeta.DiagnosticValueRole), "diagnostic_evm_proxy_not_decoder_truth"), ...
    "EVM-derived SINR must stay diagnostic and mathematically traceable without becoming decoder truth.");

ok = true;
end
