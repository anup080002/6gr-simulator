localPreflight(cfg);
state=struct();
if preflightOnly
    if nargin>=3
        mkdir(outputRoot);
        state=localRetainedBeamPreflight(cfg,outputRoot,retainedSIB1Path);
    end
    ok=true; return;
end
mkdir(outputRoot);
[~,hooks]=testSharedPUSCHChannelArtifacts("integration_hooks");
[~,tag]=fileparts(outputRoot);
