function state=localComplete(state,item)
hooks=state.TestN40Hooks;
switch string(item.Kind)
    case "PBCH"
        state=hooks.CompleteEvents(state,item);
        state=localBindOriginalSSBSelection(state,item);
    case "CSIRS"
        [state,row,reception,csi]=sixgr.truth.completeSharedCSIRSReception(state,item);
        save(fullfile(state.TestRoot,'original_csirs26.mat'),'item','row','reception','csi','-v7.3');
        assert(row.Slot==26 && row.DLMeasurementAuthorityEligible && ...
            row.ResultAvailableAtSample<=state.SharedWaveformStream.Events.NextSampleIndex);
        assert(row.CSIRSReceivedEVMAvailable && row.CSIRSReceivedEVMSamplesCount>0 && ...
            row.CSIRSReceivedEVMReferencePlane=="internal_physical_receive_element_before_RX_front_end", ...
            'test:N40OriginalCSIReceiveEVM','Original CSI26 receive-pair status: %s.', ...
            string(row.CSIRSReceivedEVMStatus));
        for flag=["RFConformanceQualified","StandardizedAccuracyQualified", ...
                "PowerUnitQualified","StandardizedReferencePointQualified","HardwareQualified"]
            assert(isequal(row.("CSIRSReceivedEVM"+flag),false), ...
                'The original internal receive-error diagnostic is not RF/reference-plane qualification.');
        end
        assert(row.ControlEVMSamplesCount>0 && ...
            row.ControlEVMSamplesContentSHA256~=row.CSIRSReceivedEVMSamplesContentSHA256, ...
            'Original TX and received aggregate CSI pairs must retain separate bindings.');
        rxPairsPath=fullfile(state.TestRoot,row.CSIRSReceivedEVMPairsCSV);
        assert(isfile(rxPairsPath) && ...
            sixgr.util.sha256File(rxPairsPath)==row.CSIRSReceivedEVMPairsCSVSHA256);
        state.TestN40CSI=row;
    case "PDCCH"
        if string(item.Context.Direction)=="UL"
            % Use the production received-assignment path explicitly; the
            % legacy generic UCI fixture also contains raw-TB branches.
            state=sixgr.truth.PDCCHControlRuntime.completeShared(state,item,hooks.ControlLog);
        elseif string(item.Context.Key)==string(sixgr.util.structGet(state,'TestContinuationControlKey',""))
            state=hooks.CompleteCSIControl(state,item);
        else
            state=sixgr.truth.PDCCHControlRuntime.completeShared(state,item,hooks.ControlLog);
        end
    case "PDSCH"
        if string(item.Context.Key)==string(sixgr.util.structGet(state,'TestContinuationControlKey',""))
            state=localCompleteN40CSIData(state,item);
        else
            state=sixgr.truth.SharedDataCompletionRuntime.complete(state,item,hooks.ControlLog);
            plans=sixgr.util.structGet(state,'SharedCompletedDataPlans',{});
            assert(~isempty(plans),'test:N40EarlyCSIPrefixReceive', ...
                'Retain a missed DCI or failed completion instead of authoring HARQ bits.');
            plan=plans{end};
            state.TestN40CompletedPrefix{end+1,1}=plan;
            sourceSlot=item.Context.Prepared.RequestBinding.StartSlotIndex;
            save(fullfile(state.TestRoot,sprintf('original_prefix_pdsch_%d.mat',sourceSlot)), ...
                'item','plan','-v7.3');
        end
    case "BindSRSPower"
        state=sixgr.truth.bindSharedSRSPower(state,item);
    case "TRS"
        % Preserve both original captures; the borrowed helper's convenience
        % file retains only the latest tracking reception.
        save(fullfile(state.TestRoot,sprintf('original_trs_%d.mat',item.Context.Slot)), ...
            'item','-v7.3');
        state=hooks.CompleteEvents(state,item);
    case "SRS"
        state=hooks.CompleteEvents(state,item);
        row=state.TestContinuationReferences{end};
        assert(row.Slot==45);
