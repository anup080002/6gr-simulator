function [ok,state]=testN40SharedRLCSTATUSRecovery(preflightOnly,outputRoot,retainedSIB1Path)
% Actual selected n40 CSI26 -> PUCCH44 -> earliest admitted PF/DCI/PDSCH;
% Original reference prefix ends51; configured reverse STATUS episode ends<=80.
% SSB/MIB/SIB1, CSI-RS, TRS, data and UCI use one physical stream. The
% connected identity and initial TAG are explicit component inputs at41;
% this test does not execute RA/RRC or qualify a full60-slot scenario.
% TS38.214 V18.8.0 5.2.2.5: this multi-resource periodic CSI reference is
% at least5*2^mu=10 slots old. Report44 uses reference34, selecting CSI26.
% MCS slew and first/steady spatial confirmation are simulator policies.
if nargin<1, preflightOnly=false; end
validateattributes(preflightOnly,{'logical'},{'scalar'});
setup6GRSimToolkit('Verbose',false);
repo=fileparts(fileparts(mfilename('fullpath')));
if nargin<2
    folder=fullfile(repo,'logs','n40_shared_rlc_status_recovery');
    if ~isfolder(folder), mkdir(folder); end
    outputRoot=tempname(folder);
end
