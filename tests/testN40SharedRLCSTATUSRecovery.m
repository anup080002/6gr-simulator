    "n40_early_received_csi_component_"+string(tag),scenario.ConfigHash);
cfg.run.rootRunFolder=outputRoot;
cfg.run.runTag=char(identity.RunID); cfg.run.executionID=char(identity.ExecutionID);
cfg.run.scenarioID=char(scenario.ScenarioID);
cfg.meta.executionID=char(identity.ExecutionID); cfg.meta.configHash=char(identity.ConfigHash);
cfg.meta.scenarioID=char(scenario.ScenarioID);
scope=['actual selected n40 20-MHz 30-kHz 20-dB nominal reference child; ' ...
    'original shared SSB/MIB/SIB1, CSI26, TRS27, normal continuous DL41:44, ' ...
    'received combined PUCCH44 and earliest admitted PF/DCI/PDSCH from46; ' ...
    'actual SRS45, joint control46, PUSCH50 and TRS47; declared initial ' ...
    'connected/TAG boundary at41, preconfigured dedicated CSI/TCI installation; ' ...
    'actual received TCI codepoint and Type-A TRS timing transfer; ' ...
    'no full RA/RRC, full60-slot completion, statistical rank/BLER or hardware qualification'];
hooks.SaveScenario(scenario,cfg,outputRoot,scope);
priorRNG=rng; restore=onCleanup(@()rng(priorRNG)); %#ok<NASGU>
rng(double(cfg.run.seed),'twister');
multi=sixgr.truth.resolveMultiUserSpec(cfg);
assert(multi.Enabled && multi.NumUsers==1 && multi.ExecutionModel=="slot_coupled_truth");
horizon=51;
assert(cfg.run.totalSlots==80&&cfg.protocol.enabled&&cfg.protocol.rlc.arq_enabled);
state=sixgr.truth.CoupledTruthRuntime.initialize(cfg,outputRoot,multi,struct(),cfg.run.totalSlots);
state.CurrentSlot=1; state.CurrentCanonicalSlot=1; state.CurrentFrame=1;
state.CurrentServingIdx(:)=1;
state.TestRoot=outputRoot; state.TestN40Hooks=hooks;
state.TestExecutionIdentity=identity;
flags={'TestPacketAccounting','TestDeferUCIDelivery','TestWithHARQ', ...
    'TestForgetCSIProducer','TestUnconsumedULCommand','TestPUCCHOnlyCompletion', ...
    'TestSeparatePUCCH','TestReceivedCSIContinuation','TestReceivedSRSContinuation', ...
    'TestRankTransitions','TestPreparedCSIAcquisitionLoss', ...
    'TestMissingSelectedSSBReference','TestSRSContinuationStarted', ...
    'TestSRSContinuationCompleted','TestSRSContinuationRejected', ...
    'TestContinuationTRSQueued','TestContinuationCompleted','TestContinuationRejected'};
for k=1:numel(flags), state.(flags{k})=false; end
state.TestWithCSI=true; state.TestIndependentCompletion=true;
state.TestIndependentSharedHARQ=true; state.TestReferenceContinuation=true;
state.TestRetainedPower=true; state.TestReceiveSIB1=true;
state.TestContinuationReferences=cell(0,1);
state.TestContinuationQueuedSRSSlots=zeros(0,1);
state.TestN40SchedulingAttempts=cell(0,1);
state.TestN40IssuedGrants=cell(0,1);
state.TestN40CompletedPrefix=cell(0,1);
state.TestN40DLApplicationIssued=false;
state.TestN40DLApplicationSlot=NaN;
state.TestN40InitialMeasuredBeamBound=false;
state.SharedPendingULGrants=repmat(struct(),0,1);
state.ScheduledDLDAILedger=struct();
[state,owner]=sixgr.truth.CoupledWaveformStream.initialize(state,cfg,{cfg});
carrier=sixgr.phy.grid.makeCarrier(cfg); fs=owner.SampleRateHz;
assert(fs==30.72e6 && owner.Events.NextSampleIndex==0);
% A declared TA command is not decoded RAR evidence. The actual received
% SSB clock and SIB1 common offset replace these empty placeholders only
% when the original full SI receiver completes (existing helper contract).
state.TestDeclaredTAG=struct('DLReference',struct(),'Offset',struct(), ...
    'ReceivedRARTiming',sixgr.phy.ra.resolveRARTimingAdvance(0,30,fs), ...
    'TimingAdvanceAvailableAtSample',NaN,'TimingAdvanceEffectiveAtSample',NaN, ...
    'TimeAlignmentExpirySampleExclusive', ...
        sixgr.phy.frame.slotStartSample(carrier,cfg.run.totalSlots,fs));
