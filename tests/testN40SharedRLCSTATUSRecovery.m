function state=localQueueJointApplications(state,cfg,dl,slot,horizon)
hooks=state.TestN40Hooks; owner=state.SharedWaveformStream;
ul=repmat(struct(),0,1); atSample=owner.Events.NextSampleIndex;
if slot==46
    [state,ul,planning]=sixgr.truth.planFutureULGrants( ...
        state,cfg,{cfg},state.SharedPendingULGrants,1,horizon);
    save(fullfile(state.TestRoot,'original_ul46_planning.mat'),'planning','ul','-v7.3');
    assert(isscalar(ul) && sixgr.truth.runtimeULGrantSlot(ul)==50 && ul.K2==4 && ...
        ul.AcceptedSRSSpatialDecision.ProducerSlot==45 && ...
        ~state.LatestULFeedback(1).Valid && isnan(state.LatestULFeedback(1).CQI), ...
        'test:N40FirstSRSUL50','Only original received SRS45 may authorize normal UL50 without invented quality.');
    hooks.AssertSRSGrant(state,cfg,ul,atSample);
end
[state,dl,ul]=sixgr.truth.planJointHARQPUSCHTiming(state,{cfg},dl,ul);
[dl,ul]=sixgr.truth.resolveJointPDCCHAdmission(state,cfg,{cfg},dl,ul);
joint=struct('Slot',slot,'DL',dl,'UL',ul); %#ok<NASGU>
save(fullfile(state.TestRoot,sprintf('original_joint_control_%d.mat',slot)),'joint','-v7.3');
[state,qualified,queuedDL]=sixgr.truth.PDCCHControlRuntime.queueShared( ...
    state,{cfg},dl,'DL',cfg.channel.snr_dB,hooks.ControlLog);
assert(isempty(qualified) && owner.Events.NextSampleIndex==atSample);
if ~isempty(ul)
    state.TestSRSContinuationStarted=true;
    state.TestSRSContinuationInitialHARQ=state.ULHarq.Stats;
    state.TestSRSContinuationExpiry=state.TestN40Boundary.TAGExpirySampleExclusive;
    [state,qualified,queuedUL]=sixgr.truth.PDCCHControlRuntime.queueShared( ...
        state,{cfg},ul,'UL',cfg.channel.snr_dB,hooks.ControlLog);
    assert(isempty(qualified) && isscalar(queuedUL) && ...
        sixgr.truth.runtimeULGrantSlot(queuedUL)==50 && owner.Events.NextSampleIndex==atSample, ...
        'test:N40UL50ControlAdmission','Retain an actual joint-admission failure, never force UL control.');
    state.TestSRSContinuationGrant=queuedUL;
    state.TestSRSContinuationAccepted=queuedUL.AcceptedSRSSpatialDecision;
    state.TestSRSContinuationDecisionSample=atSample;
end
if slot==46
    assert(state.TestSRSContinuationStarted,'test:N40UL50JointAdmission', ...
        'The real joint-control policy did not admit UL50; no received DCI may be fabricated.');
end
if isempty(queuedDL), return; end % Keep the real admission and try the next legal DL.
assert(isscalar(queuedDL));
hooks.AssertCSICapsule(queuedDL.CSIReportProvenance,state.TestContinuationAdmittedReport);
la=sixgr.util.structGet(state,'TestPublishedDLStates',repmat({struct()},state.NumUsers,1));
state=sixgr.truth.queueSharedDataPlans(state,cfg,state.MultiUser,{cfg},queuedDL, ...
    'DL',cfg.channel.snr_dB,queuedDL.Frame,la);
state.TestContinuationIssuedGrant=queuedDL;
state.TestContinuationControlKey=sixgr.truth.GrantPreparation.sharedGrantControlKey(queuedDL,'DL');
state.TestN40IssuedGrants{end+1,1}=queuedDL;
state.TestN40DLApplicationIssued=true;
state.TestN40DLApplicationSlot=slot;
end

