function ok = testFRCTargetCrossingQualification()
%TESTFRCTARGETCROSSINGQUALIFICATION Guard fixed-sample SNR-bracket logic.

setup6GRSimToolkit("AddSubfolders", false, "Verbose", false, ...
    "RunToolboxChecks", false);

confidence = 0.95;
targetBLER = 1e-5;
numTB = ceil(log((1 - confidence) / 2) / log(1 - targetBLER));
blockErrors = [10; 2; 0];
snr = [-1; 0; 1];
metric = blockErrors ./ numTB;
lower = zeros(size(metric));
upper = zeros(size(metric));
method = strings(size(metric));
for index = 1:numel(metric)
    [lower(index), upper(index), ~, ~, method(index)] = ...
        sixgr.conformance.metricConfidenceBounds( ...
        "block_error_rate", blockErrors(index), numTB, [], [], ...
        confidence, 1);
end

requirement = struct( ...
    "metric", "block_error_rate", ...
    "target_fraction", targetBLER, ...
    "comparator", "less_than_or_equal");
[measured, info] = sixgr.conformance.qualifyTargetCrossing( ...
    snr, metric, lower, upper, repmat(numTB, size(snr)), method, ...
    true, requirement, 0, 1, confidence);

assert(logical(info.StatisticallyQualified), ...
    ["A low-BLER crossing must qualify when the prespecified low endpoint " ...
    "is confidently above target and the high endpoint is confidently below."]);
assert(logical(info.LowerEndpointConfidenceSeparates) && ...
    logical(info.UpperEndpointConfidenceSeparates), ...
    "Both directional endpoint comparisons must support the bracket.");
assert((upper(1) - lower(1)) / 2 > targetBLER / 2, ...
    "The regression fixture must exercise a lower endpoint with a wide CI.");
assert(~logical(info.MetricIntervalHalfWidthUsedForQualification) && ...
    logical(info.SNRBracketWidthUsedForQualification), ...
    ["Metric half-width must not reject a confidence-separated low-BLER " ...
    "endpoint; SNR bracket width is the project-gate precision."]);
assert(abs(double(info.BracketWidth_dB) - 2) <= 1e-12 && ...
    logical(info.BracketPrecisionTargetMet) && ...
    logical(info.BracketWithinTolerance), ...
    "The qualified bracket must be contained in required SNR +/- tolerance.");
assert(double(info.JointConfidenceLevel) == confidence && ...
    abs(double(info.EndpointOneSidedConfidenceLevel) - 0.975) <= 1e-12 && ...
    info.MultiplicityControl == ...
    "bonferroni_two_prespecified_tolerance_endpoints", ...
    "The two endpoint decisions must preserve 95% family-wise confidence.");
assert(isfinite(measured) && abs(measured) <= 1, ...
    "The reported point-estimate crossing must remain inside the bracket.");

% The same directional rule applies to a throughput target, with the
% inequalities reversed: low SNR confidently misses, high SNR attains.
throughputSuccesses = [60; 70; 80];
throughputTrials = 100;
throughputMetric = throughputSuccesses ./ throughputTrials;
throughputLower = zeros(size(throughputMetric));
throughputUpper = zeros(size(throughputMetric));
throughputMethod = strings(size(throughputMetric));
for index = 1:numel(throughputMetric)
    delivered = [ones(throughputSuccesses(index), 1); ...
        zeros(throughputTrials - throughputSuccesses(index), 1)];
    attempts = ones(throughputTrials, 1);
    [throughputLower(index), throughputUpper(index), ~, ~, ...
            throughputMethod(index)] = ...
        sixgr.conformance.metricConfidenceBounds( ...
        "fraction_of_maximum_throughput", ...
        throughputSuccesses(index), throughputTrials, ...
        delivered, attempts, confidence, 1);
end
throughputRequirement = struct( ...
    "metric", "fraction_of_maximum_throughput", ...
    "target_fraction", 0.7, ...
    "comparator", "greater_than_or_equal");
[throughputCrossing, throughputInfo] = ...
    sixgr.conformance.qualifyTargetCrossing( ...
    snr, throughputMetric, throughputLower, throughputUpper, ...
    repmat(throughputTrials, size(snr)), throughputMethod, true, ...
    throughputRequirement, 0, 1, confidence);
assert(logical(throughputInfo.StatisticallyQualified) && ...
    isfinite(throughputCrossing) && abs(throughputCrossing) <= 1, ...
    "Throughput must use the confidence-separated tolerance bracket.");

% A receiver that already attains the target at the lower tolerance
% boundary is better than the symmetric project anchor, but it cannot pass
% the nonnormative symmetric crossing check.
tooGoodLower = lower;
tooGoodUpper = upper;
tooGoodMetric = metric;
tooGoodMetric(1) = 0;
tooGoodLower(1) = 0;
tooGoodUpper(1) = targetBLER / 2;
[~, tooGoodInfo] = sixgr.conformance.qualifyTargetCrossing( ...
    snr, tooGoodMetric, tooGoodLower, tooGoodUpper, ...
    repmat(numTB, size(snr)), method, true, requirement, 0, 1, confidence);
assert(~logical(tooGoodInfo.StatisticallyQualified) && ...
    ~logical(tooGoodInfo.LowerEndpointConfidenceSeparates), ...
    ["Exceeding the standard must not be relabelled as a standards failure, " ...
    "but the separate symmetric project diagnostic must remain false."]);

runnerSource = fileread(which("sixgr.conformance.runFRCPoint"));
assert(contains(runnerSource, ...
    "sixgr.conformance.qualifyTargetCrossing") && ...
    contains(runnerSource, "sweep.ConfidenceLower") && ...
    contains(runnerSource, ...
    '"RequiredPointHalfWidthUsedForQualification", false') && ...
    ~contains(runnerSource, ...
    "all(precisionTargetMet(bracket:bracket+1))"), ...
    ["The runner must use simultaneous endpoint bounds and must not revive " ...
    "the obsolete metric-half-width crossing veto."]);

fprintf("%s\n", ...
    "FRCTargetCrossingQualification: fixed-sample confidence-separated " + ...
    "SNR brackets passed.");
ok = true;
end
