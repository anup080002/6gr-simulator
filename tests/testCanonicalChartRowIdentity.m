function ok = testCanonicalChartRowIdentity()
%TESTCANONICALCHARTROWIDENTITY Guard physical-event and aggregation primary keys.

setup6GRSimToolkit("Verbose", false);

beamT = table( ...
    ["DL";"DL";"DL";"UL"], [NaN;NaN;NaN;NaN], [1;1;2;1], ...
    [true;true;true;true], [true;true;false;true], ...
    ["applied_runtime_value";"applied_runtime_value";"applied_runtime_value";"applied_runtime_value"], ...
    ["not_applicable";"not_applicable";"not_applicable";"applied_runtime_value"], ...
    [64;64;64;4], [2;2;2;2], ...
    'VariableNames', ["direction","cell_id","ue_id","beamforming_applied", ...
    "beam_hit","applied_beam_truth_classification", ...
    "applied_precoder_pmi_truth_classification","precoding_num_ports", ...
    "precoding_num_layers"]);
beamAgg = sixgr.truth.aggregateBeamPrecoderEvidence(beamT);
assert(height(beamAgg) == 3, ...
    "Missing CellID must not split repeated DL/UE observations into duplicate aggregate rows.");
dlUe1 = beamAgg.direction == "DL" & beamAgg.ue_id == 1;
assert(nnz(dlUe1) == 1 && beamAgg.trial_row_count(dlUe1) == 2, ...
    "DL UE-1 aggregate must preserve both runtime source observations.");
assert(height(unique(beamAgg(:, ["direction","cell_id","ue_id"]), "rows")) == height(beamAgg), ...
    "Beam aggregate natural keys must be unique.");
mimoRank = sixgr.truth.aggregateMIMORankUtilization(beamT);
assert(height(mimoRank) == 2 && ...
    mimoRank.trial_row_count(mimoRank.direction == "DL") == 3 && ...
    mimoRank.trial_row_count(mimoRank.direction == "UL") == 1 && ...
    height(unique(mimoRank, "rows", "stable")) == height(mimoRank), ...
    "MIMO rank utilization must aggregate missing-cell observations by direction/rank without duplicate rows.");

trialT = table([1;1;2], [20;20;20], [1;1;1], [16;18;20], ...
    'VariableNames', ["UEID","SNR_dB","Frame","Slot"]);
relationT = sixgr.visual.buildTrialRelationshipRows(trialT, [0;0;0], [0;0;0], ...
    "DL", "air_interface/csv/dl_pdsch_trials.csv");
assert(height(relationT) == 3 && height(unique(relationT, "rows")) == 3, ...
    "Coincident BER/BLER samples must retain source-row identity instead of becoming duplicate CSV rows.");
assert(all(relationT.SourceRow == (1:3).'), ...
    "Relationship plot rows must preserve exact source-row lineage.");

powerT = table([100;NaN;100], [0.1;0.2;0.1], ["cell";"ue";"cell"], ...
    [1;1;1], ["DL";"DL";"DL"], [1;2;3], ...
    'VariableNames', ["useful_bits","cumulative_energy_J","entity_type", ...
    "entity_id","direction","timestamp_sim_ms"]);
energyT = sixgr.visual.buildEnergyThroughputChartTable(powerT, ...
    "rf/csv/power_energy_table.csv");
assert(height(energyT) == 2 && isequal(energyT.SourceRow, [1;3]), ...
    "Energy/throughput chart construction must filter row-wise without cross-row numeric pairing.");
assert(height(unique(energyT, "rows")) == height(energyT), ...
    "Coincident energy points must retain source-row lineage.");

[statDL, noteDL] = sixgr.truth.beamMetricStatisticIdentity("p2_failure_rate", "DL", 20);
[statUL, noteUL] = sixgr.truth.beamMetricStatisticIdentity("p2_failure_rate", "UL", 20);
assert(statDL ~= statUL && contains(statDL, "direction_dl") && contains(statUL, "direction_ul"), ...
    "Directional beam aggregates must have distinct natural-key statistics.");
assert(contains(noteDL, "Direction=DL") && contains(noteUL, "Direction=UL"), ...
    "Directional beam statistic identity must retain human-readable scope notes.");

ok = true;
fprintf("testCanonicalChartRowIdentity: PASS\n");
end
