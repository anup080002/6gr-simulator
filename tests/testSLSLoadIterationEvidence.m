function ok = testSLSLoadIterationEvidence()
% Reusable S0 evidence gate; these are contract fixtures, not study rates.
seed=struct('TrafficSeed',17,'ChannelSeed',29);
baseHash=string(repmat('b',1,64));
calHash=string(repmat('c',1,64));
expected=struct('ArrivalRatePerCell_s',2,'SeedBundle',seed, ...
    'PlannedExecutionArchitecture',"waveform");
d=struct('WaveformBacked',true,'ProxyPHYActive',false,'FallbackUsed',false, ...
    'SeedBundle',seed,'SchedulerGrants',localGrant(), ...
    'ResourceOpportunityTable',localOpportunity(), ...
    'TrafficArrivalEvents',localArrivals(), ...
    'TrafficArrivalStreamID',"fixture_ftp3_stream_17", ...
    'TrafficDefinitionSource', ...
        "configured_fixed_file_continuous_time_poisson_ftp3", ...
    'TrafficDeterministic',true, ...
    'TrafficModel',"ftp3",'TrafficArrivalRatePerCell_s',2, ...
    'LoadCalibrationBaseConfigSHA256',baseHash,'DecodeUnavailableUL',0);
result=struct('Ok',true,'Details',d);
identity=sixgr.system.validateS0LoadIteration(result,expected);
assert(identity.PHYExecutionMode=="waveform" && ...
    identity.BaseConfigSHA256==baseHash && identity.CalibrationSHA256=="");

bad=result; bad.Details.ProxyPHYActive=true;
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=result; bad.Details.SeedBundle.TrafficSeed=18;
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=result; bad.Details.SchedulerGrants=struct();
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=result; bad.Details.SchedulerGrants=bad.Details.SchedulerGrants([],:);
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=result; bad.Details.ResourceOpportunityTable=bad.Details.ResourceOpportunityTable([],:);
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=result; bad.Details.TrafficArrivalEvents=bad.Details.TrafficArrivalEvents([],:);
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
zero=result;
zero.Details.TrafficArrivalEvents=zero.Details.TrafficArrivalEvents([],:);
zero.Details.SchedulerGrants=zero.Details.SchedulerGrants([],:);
zeroIdentity=sixgr.system.validateS0LoadIteration(zero,expected);
assert(zeroIdentity.PHYExecutionMode=="waveform", ...
    'A schema-backed zero-file Poisson realization must remain measurable.');
bad=result; bad.Details.TrafficArrivalStreamID="";
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=result; bad.Details.ResourceOpportunityTable.Source="fabricated_from_grants";
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=result; bad.Details.SchedulerGrants.WaveformReplayExecuted=false;
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=result; bad.Details.SchedulerGrants.PHYDecisionRole="calibrated_sls_estimate";
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=result; bad.Details.SchedulerGrants.TBSBits=0;
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=result; bad.Details.SchedulerGrants=[bad.Details.SchedulerGrants;bad.Details.SchedulerGrants];
bad.Details.SchedulerGrants.WaveformReplayExecuted(2)=false;
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');

abstract=result;
abstract.Details.WaveformBacked=false;
abstract.Details.ProxyPHYActive=true;
abstract.Details.ExecutionBackend="CALIBRATED_LINK_ABSTRACTION";
abstract.Details.CalibrationQualified=true;
abstract.Details.CalibrationSHA256=calHash;
abstract.Details.SourceClassification="calibrated_sls_estimate_not_waveform_truth";
abstract.Details.SchedulerGrants.PHYDecisionRole="calibrated_sls_estimate";
abstract.Details.SchedulerGrants.WaveformReplayExecuted=false;
abstract.Details.SchedulerGrants.CalibrationQualified=true;
abstract.Details.SchedulerGrants.CalibrationSHA256=calHash;
abstract.Details.SchedulerGrants.CalibrationKeySHA256=calHash;
abstract.Details.SchedulerGrants.SourceClassification= ...
    "calibrated_sls_estimate_not_waveform_truth";
expected.PlannedExecutionArchitecture="calibrated_link_abstraction";
identity=sixgr.system.validateS0LoadIteration(abstract,expected);
assert(identity.PHYExecutionMode=="CALIBRATED_LINK_ABSTRACTION" && ...
    identity.CalibrationSHA256==calHash);
bad=abstract; bad.Details.CalibrationQualified=false;
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=abstract; bad.Details.SourceClassification="waveform_truth";
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=abstract; bad.Details.SchedulerGrants.CalibrationKeySHA256="";
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=abstract; bad.Details.SchedulerGrants.CalibrationQualified=false;
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
bad=abstract; bad.Details.SchedulerGrants.CalibrationSHA256=baseHash;
localReject(@()sixgr.system.validateS0LoadIteration(bad,expected), ...
    'sixgr:system:S0LoadEvidence');
localReject(@()sixgr.system.validateS0LoadIteration(abstract, ...
    struct('ArrivalRatePerCell_s',2,'SeedBundle',seed, ...
    'PlannedExecutionArchitecture',"waveform")), ...
    'sixgr:system:S0LoadEvidence');
ok=true; fprintf('SLS_LOAD_ITERATION_EVIDENCE_PASS\n');
end

