end

function T=localArrivals()
T=table("fixture_arrival_1",1,0.01,1,100,800,"DL",17, ...
    "fixture_ftp3_stream_17","fixed_file_continuous_time_poisson", ...
    'VariableNames',{'ArrivalID','ArrivalTTI','ArrivalTime_s','UEID', ...
    'FileSizeBytes','OfferedBits','Direction','Seed','ArrivalStreamID', ...
    'ArrivalProcess'});
end

function localReject(fn,id)
try
    fn();
catch ME
    assert(strcmp(ME.identifier,id),'Expected %s, got %s: %s', ...
        id,ME.identifier,ME.message);
    return
end
error('test:MissingRejection','Expected %s.',id);
end
