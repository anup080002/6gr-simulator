function ok = testPDSCHPTRSIndicesIndependent()
%TESTPDSCHPTRSINDICESINDEPENDENT Compare all present rows to local oracle.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
vectors = readPDSCHVectorTable("pdsch_ptrs_test_vectors.csv");
present = vectors(str2double(vectors.ExpectedPTRSPresent) == 1, :);
assert(height(present) == 48, ...
    "All 48 frozen PT-RS-present rows must execute the index oracle.");

totalIndices = 0;
for i = 1:height(present)
    nPRB = str2double(present.NPRB(i));
    duration = str2double(present.PDSCHDuration(i));
    if present.MappingType(i) == "A"
        dmrsSymbols = 2;
    else
        dmrsSymbols = 0;
    end
    request = struct( ...
        "PRBSet", 0:(nPRB - 1), ...
        "SymbolAllocation", [0 duration], ...
        "DMRSSymbols", dmrsSymbols, ...
        "TimeDensity", str2double(present.TimeDensity(i)), ...
        "FrequencyDensity", str2double(present.FrequencyDensity(i)), ...
        "REOffset", present.REOffset(i), ...
        "GridNumPRB", nPRB);
    actual = sixgr.pdsch.PDSCHPTRSResolver.resolveIndices(request);
    oracle = sixgr.pdsch.oracle.PTRSIndexSpec.resolve(request);
    assert(actual.IndexBase == "zero_based" && ...
        oracle.IndexBase == "zero_based", ...
        "PT-RS index convention mismatch for %s.", present.CaseID(i));
    assert(isequal(actual.Indices0Based, oracle.Indices0Based), ...
        "PT-RS linear-index mismatch for %s.", present.CaseID(i));
    assert(isequal(actual.Coordinates0Based, ...
        oracle.Coordinates0Based), ...
        "PT-RS coordinate mismatch for %s.", present.CaseID(i));
    assert(isequal(actual.Symbols0Based, oracle.Symbols0Based) && ...
        isequal(actual.PRBSet0Based, oracle.PRBSet0Based), ...
        "PT-RS time/frequency selection mismatch for %s.", ...
        present.CaseID(i));
    assert(~any(ismember(actual.Coordinates0Based(:, 2), dmrsSymbols)), ...
        "PT-RS collides with DM-RS for %s.", present.CaseID(i));
    assert(all(actual.Coordinates0Based(:, 1) >= 0) && ...
        all(actual.Coordinates0Based(:, 1) < 12 * nPRB), ...
        "PT-RS lies outside the scheduled bandwidth for %s.", ...
        present.CaseID(i));
    totalIndices = totalIndices + numel(actual.Indices0Based);
end
assert(totalIndices > 0, ...
    "Independent PT-RS comparison did not execute any RE indices.");

% Regression: TS 38.211 restarts the PT-RS time-density pattern after
% every DM-RS occasion.  The former first-DM-RS-only phase was wrong for
% an odd separation between later DM-RS symbols.
carrier = nrCarrierConfig;
carrier.NCellID = 42;
carrier.NSizeGrid = 4;
carrier.NStartGrid = 0;
carrier.NSlot = 0;
pdsch = nrPDSCHConfig;
pdsch.NID = carrier.NCellID;
pdsch.RNTI = 4660;
pdsch.PRBSet = [0 2 3];
pdsch.SymbolAllocation = [0 14];
pdsch.MappingType = "A";
pdsch.NumLayers = 1;
pdsch.DMRS.DMRSConfigurationType = 1;
pdsch.DMRS.DMRSTypeAPosition = 2;
pdsch.DMRS.DMRSAdditionalPosition = 2;
pdsch.DMRS.DMRSLength = 1;
pdsch.DMRS.DMRSPortSet = 0;
pdsch.DMRS.NIDNSCID = carrier.NCellID;
pdsch.DMRS.NSCID = 0;
pdsch.EnablePTRS = true;
pdsch.PTRS.TimeDensity = 2;
pdsch.PTRS.FrequencyDensity = 2;
pdsch.PTRS.REOffset = "00";
pdsch.PTRS.PTRSPortSet = 0;
dmrsSubscripts = nrPDSCHDMRSIndices(carrier,pdsch, ...
    "IndexStyle","subscript","IndexBase","0based");
dmrsSymbols = unique(double(dmrsSubscripts(:,2))).';
request = struct( ...
    "PRBSet",double(pdsch.PRBSet), ...
    "SymbolAllocation",double(pdsch.SymbolAllocation), ...
    "DMRSSymbols",dmrsSymbols, ...
    "TimeDensity",double(pdsch.PTRS.TimeDensity), ...
    "FrequencyDensity",double(pdsch.PTRS.FrequencyDensity), ...
    "REOffset",string(pdsch.PTRS.REOffset), ...
    "GridNumPRB",double(carrier.NSizeGrid), ...
    "RNTI",double(pdsch.RNTI), ...
    "DMRSConfigurationType",double(pdsch.DMRS.DMRSConfigurationType), ...
    "AssociatedDMRSPort",double(pdsch.PTRS.PTRSPortSet));
actual = sixgr.pdsch.PDSCHPTRSResolver.resolveIndices(request);
toolboxSubscripts = nrPDSCHPTRSIndices(carrier,pdsch, ...
    "IndexStyle","subscript","IndexBase","0based");
K = double(carrier.NSizeGrid)*12;
toolboxIndices = double(toolboxSubscripts(:,1) ...
    + K*toolboxSubscripts(:,2));
assert(isequal(actual.Indices0Based,toolboxIndices), ...
    "PT-RS restart-after-each-DM-RS regression mismatch.");
ok = true;
end
