function ok = testCalibrationProvenanceHonesty()
%TESTCALIBRATIONPROVENANCEHONESTY Keep calibration provenance honest for partial runs.

setup6GRSimToolkit("Verbose", false);

tmpTruth = fullfile(pwd,'results','sls','calibration_provenance_honesty', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
mkdir(tmpTruth);
fprintf('CALIBRATION_PROVENANCE_EVIDENCE_ROOT=%s\n',tmpTruth);
[cfg,nSlots] = e2eReceivedAccessConfig(tmpTruth,2,"mmtc");
cfg.run.shortRun = true;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;

repTruth = sixgr_run_3gpp_full_campaign(cfg, ...
    "ResultsRoot", tmpTruth, ...
    "Verbose", false, ...
    "SetupToolboxChecks", false, ...
    "OnlyE2E", true, ...
    "RunE2EStackProbe", true, ...
    "E2EDuration_s", nSlots*sixgr.time.slotDurationSec(cfg), ...
    "E2EMaxSlots", nSlots, ...
    "E2EUECount", 2, ...
    "E2ETrafficModel", "mmtc", ...
    "E2EAirModel", "truth", ...
    "E2EEnableAI", false, ...
    "E2ESaveFigures", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "VerifyArtifacts", false, ...
    "GenerateCampaignPlots", false, ...
    "E2EStrictValidation", false, ...
    "E2ETruthFastAWGNPath", false, ...
    "E2ETruthMaxSlots", nSlots, ...
    "LinkSNR_dB", 30);

assert(repTruth.Ok && height(repTruth.E2E.ReceivedAccessBindings)==2 && ...
    numel(unique(repTruth.E2E.SchedulerTraceTable.UE))==2, ...
    'Non-strict truth must retain real per-UE received access and executed data.');
assert(all(ismember(["DL","UL"],upper(string(repTruth.E2E.SchedulerTraceTable.Direction)))), ...
    'Provenance validation must retain the original bidirectional traffic coverage.');

runTruth = char(string(repTruth.RunFolder));
assert(exist(fullfile(runTruth, "meta", "calibration_source.json"), "file") ~= 2, ...
    "Truth-only E2E runs must skip calibration provenance export.");
assert(exist(fullfile(runTruth, "calibration"), "dir") ~= 7, ...
    "Truth-only E2E runs must not create a calibration artifact folder.");

tmpLut = tempname;
mkdir(tmpLut);
cLut = onCleanup(@() rmdir(tmpLut, "s")); %#ok<NASGU>

threw = false;
try
    sixgr_run_3gpp_full_campaign(cfg, ...
        "ResultsRoot", tmpLut, ...
        "Verbose", false, ...
        "SetupToolboxChecks", false, ...
        "OnlyE2E", true, ...
        "RunE2EStackProbe", true, ...
        "E2EDuration_s", 0.02, ...
        "E2EMaxSlots", 24, ...
        "E2EUECount", 2, ...
        "E2ETrafficModel", "xr", ...
        "E2EAirModel", "lut", ...
        "E2EEnableAI", false, ...
        "E2ESaveFigures", false, ...
        "UseMexAcceleration", false, ...
        "AutoBuildMexAcceleration", false, ...
        "VerifyArtifacts", false, ...
        "GenerateCampaignPlots", false, ...
        "E2EStrictValidation", false); %#ok<NASGU>
catch ME
    threw = strcmp(ME.identifier, "sixgr:campaign:ProxyModeRemoved");
end
assert(threw, "Removed LUT calibration/provenance paths must fail closed.");

ok = true;
end
