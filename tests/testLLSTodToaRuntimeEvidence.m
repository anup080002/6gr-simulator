function ok = testLLSTodToaRuntimeEvidence()
%TESTLLSTODTOARUNTIMEEVIDENCE Verify same-flow ToD/ToA evidence from active LLS DL/UL trials and reports.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

[cfg, state, grant] = localPrepareRuntime(tmp);
[cfgDL, state] = sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg, state, 1, "DL");
[cfgUL, state] = sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg, state, 1, "UL");

dl = sixgr.link.runDLPDSCHThroughput(cfgDL, ...
    "NumFrames", 1, ...
    "SNR_dB", cfg.channel.snr_dB, ...
    "GrantSnapshot", grant, ...
    "InterferenceBundle", struct([]));
ul = sixgr.link.runULPUSCHThroughput(cfgUL, ...
    "NumFrames", 1, ...
    "SNR_dB", cfg.channel.snr_dB, ...
    "GrantSnapshot", grant, ...
    "InterferenceBundle", struct([]));

localAssertTodToaRawRow(dl.TrialTable, "DL");
localAssertTodToaRawRow(ul.TrialTable, "UL");

trialT = localVertcatTablesByName(dl.TrialTable, ul.TrialTable);
signalArtifacts = sixgr.truth.exportLLSLiveSignalChainTables(fullfile(tmp, "run"), trialT, table(), struct());
stageT = readtable(char(signalArtifacts.StageTracePath), "VariableNamingRule", "preserve", "Delimiter", ",");
assert(all(ismember({'BSAntennaArrayClass','UEAntennaArrayClass','PropagationDistance_m','ToD_s','ToA_s','ToAEstimate_s','ChannelDelaySource','AntennaGeometrySource','SameFlowEvidenceSource'}, stageT.Properties.VariableNames)), ...
    "Live stage trace must preserve the same-flow antenna and ToD/ToA evidence columns.");
assert(height(stageT) == 2, ...
    "Live stage trace must preserve both DL and UL rows for same-flow ToD/ToA validation.");
assert(all(isfinite(double(stageT.ToD_s))) && all(isfinite(double(stageT.ToA_s))) && all(double(stageT.ToA_s) >= double(stageT.ToD_s)), ...
    "Live stage trace must export finite ToD/ToA values with ToA not preceding ToD.");

rawTrials = struct("DL", dl.TrialTable, "UL", ul.TrialTable);
mobilityArtifacts = sixgr.truth.CoupledTruthRuntime.mobilityArtifacts(state);
derivedArtifacts = sixgr.truth.exportLLSLiveDerivedTables(cfg, fullfile(tmp, "run"), rawTrials, struct(), mobilityArtifacts, struct("AntennaConfigResolvedTable", state.AntennaConfigResolvedTable));
todToaT = readtable(char(derivedArtifacts.TodToaTracePath), "VariableNamingRule", "preserve", "Delimiter", ",");
timingT = readtable(char(derivedArtifacts.TimingPositioningEvidencePath), "VariableNamingRule", "preserve", "Delimiter", ",");

assert(height(todToaT) == 2 && all(strcmpi(string(todToaT.ChannelArrayModel), "nrtdl_runtime_geometry_correlation_channel")), ...
    "ToD/ToA trace export must preserve both DL and UL active rows and disclose the active TDL channel model.");
assert(all(strlength(string(todToaT.ToDSource)) > 0) && all(strlength(string(todToaT.ToASource)) > 0) && ...
    all(strlength(string(todToaT.ChannelDelaySource)) > 0) && all(strlength(string(todToaT.SameFlowEvidenceSource)) > 0), ...
    "ToD/ToA trace export must disclose same-flow source provenance.");
assert(height(timingT) == 2 && all(double(timingT.FiniteToDCount) >= 1) && all(double(timingT.FiniteToACount) >= 1), ...
    "Timing/positioning runtime evidence export must summarize both directions with finite ToD/ToA counts.");
assert(all(contains(string(timingT.Notes), "ToD is the active slot-start runtime reference")), ...
    "Timing/positioning runtime evidence must explain the truthful ToD/ToA semantics.");

ok = true;
end

function T = localVertcatTablesByName(varargin)
T = varargin{1};
for k = 2:nargin
    T = localAppendTableByName(T, varargin{k});
end
end

function T = localAppendTableByName(A, B)
vars = union(string(A.Properties.VariableNames), string(B.Properties.VariableNames), "stable");
for i = 1:numel(vars)
    name = char(vars(i));
    hasA = ismember(name, A.Properties.VariableNames);
    hasB = ismember(name, B.Properties.VariableNames);
    if ~hasA && hasB
        A.(name) = localMissingColumnLike(B.(name), height(A));
    elseif hasA && ~hasB
        B.(name) = localMissingColumnLike(A.(name), height(B));
    end
end
A = A(:, cellstr(vars));
B = B(:, cellstr(vars));
T = [A; B];
end

function col = localMissingColumnLike(reference, nRows)
if isstring(reference)
    col = strings(nRows, 1);
elseif islogical(reference)
    col = false(nRows, 1);
elseif isnumeric(reference)
    col = nan(nRows, 1);
else
    col = repmat(missing, nRows, 1);
end
end
function localAssertTodToaRawRow(T, direction)
assert(istable(T) && height(T) == 1, ...
    "Expected one raw %s trial row for ToD/ToA validation.", direction);
requiredVars = { ...
    'PropagationDistance_m','GeometricPropagationDelay_s','DominantPathDelay_s','ChannelFilterDelay_s','PropagationDelay_s', ...
    'ToD_s','ToA_s','ToAEstimate_s','TimingEstimateUsed','ChannelArrayModel','ChannelUsesCountOnlyAntennaModel','ChannelArrayHandlingStatus','ChannelGeometryCouplingLevel','GeometryAdapterType','ChannelUsesSameRuntimeAntennaAssumptions', ...
    'ToDSource','ToASource','ToAEstimateSource','ChannelDelaySource','AntennaGeometrySource','RuntimeTraceSource','SameFlowEvidenceSource'};
assert(all(ismember(requiredVars, T.Properties.VariableNames)), ...
    "Raw %s trial row must expose same-flow ToD/ToA evidence columns.", direction);
assert(isfinite(double(T.PropagationDistance_m(1))) && double(T.PropagationDistance_m(1)) > 0, ...
    "Raw %s trial row must export finite propagation distance.", direction);
assert(isfinite(double(T.GeometricPropagationDelay_s(1))) && double(T.GeometricPropagationDelay_s(1)) > 0, ...
    "Raw %s trial row must export finite geometric propagation delay.", direction);
assert(isfinite(double(T.ToD_s(1))) && isfinite(double(T.ToA_s(1))) && double(T.ToA_s(1)) >= double(T.ToD_s(1)), ...
    "Raw %s trial row must export a finite ToD/ToA pair.", direction);
assert(strcmpi(char(string(T.ToDSource(1))), "runtime_slot_start_reference") && ...
    strcmpi(char(string(T.ToASource(1))), "runtime_geometry_plus_channel_path_delay"), ...
    "Raw %s trial row must disclose truthful ToD/ToA provenance.", direction);
assert(strcmpi(char(string(T.ChannelArrayModel(1))), "nrtdl_runtime_geometry_correlation_channel") && ...
    strcmpi(char(string(T.ChannelArrayHandlingStatus(1))), "adapted_geometry_backed_reduced_representation") && ...
    strcmpi(char(string(T.ChannelGeometryCouplingLevel(1))), "runtime_geometry_reduced_spatial_correlation") && ...
    strcmpi(char(string(T.GeometryAdapterType(1))), "tdl_custom_tx_rx_correlation_from_runtime_element_positions") && ...
    ~logical(T.ChannelUsesCountOnlyAntennaModel(1)) && ~logical(T.ChannelUsesSameRuntimeAntennaAssumptions(1)), ...
    "Raw %s trial row must honestly disclose the active reduced geometry-correlation TDL channel model.", direction);
end

