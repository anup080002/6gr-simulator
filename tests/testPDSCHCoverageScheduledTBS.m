function ok = testPDSCHCoverageScheduledTBS()
%TESTPDSCHCOVERAGESCHEDULEDTBS BLER truth must exercise the resolved MCS TBS.

setup6GRSimToolkit("Verbose",false,"RunToolboxChecks",false);
probe = sixgr.pdsch.PDSCHCoverageExecutor.runReceiverTruthPoint( ...
    "TDL-A", "Rank",1, "Modulation","64QAM", ...
    "MCSIndex",18, "SNRdB",45, "Seed",19021, ...
    "NumTrials",1, "PRBSet",0:5, ...
    "ExecutionLabel","scheduled_tbs_regression");

assert(probe.Passed && height(probe.TrialTable) == 1, ...
    "Scheduled-TBS regression did not execute one strict fading TX/RX trial.");
trial = probe.TrialTable(1,:);
assert(trial.BitsCompared > 40, ...
    ["PDSCH coverage still used the legacy hardcoded 40-bit block " ...
    "instead of the MCS/allocation-derived scheduled TBS."]);
assert(trial.BitsCompared <= trial.RateMatchedBits, ...
    "Scheduled TBS exceeds the materialized PDSCH rate-matched capacity.");
assert(probe.MCSIndex == "18" && probe.Modulation == "64QAM", ...
    "The executed scheduled-TBS point does not preserve its MCS authority.");
ok = true;
end
