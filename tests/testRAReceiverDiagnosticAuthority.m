function ok=testRAReceiverDiagnosticAuthority()
% Export-boundary fixtures only; physical integration is tested separately.
setup6GRSimToolkit('Verbose',false);
localCanonicalCommonProcedureMeasurements();
empty=sixgr.phy.ra.receiverDiagnostics();
assert(~empty.ReceiverDiagnosticsPresent && isnan(empty.CFOEstimateAvailable) && ...
    isnan(empty.EstimatedCFO_Hz) && isnan(empty.TimingEstimateUsed) && ...
    isnan(empty.PostEqSINRAvailable));
assert(isequaln(empty,sixgr.phy.ra.receiverDiagnostics(struct('Ok',false))), ...
    'A default failed/not-attempted flag alone is not measured receiver evidence.');
rx=struct('Ok',false,'CFOEstimateAvailable',true,'EstimatedCFO_Hz',-401.25, ...
    'CFOCorrectionApplied',true,'CFOCorrectionApplied_Hz',-401.25, ...
    'ResidualCFO_EstimatedPostCorrection_Hz',NaN, ...
    'ResidualCFOEstimateRole',"same_window_consistency_not_independent_residual", ...
    'ResidualCFOReusesAcquisitionObservation',true,'ResidualCFOEstimatorConsistency_Hz',0, ...
    'TimingEstimateUsed',true,'RawTimingEstimate_samples',7, ...
    'AppliedTimingCorrection_samples',7,'TimingEstimateSource',"received_DMRS", ...
    'ReceiverHestSINR_dB',29.3,'ReceiverHestSINRSource',"pilot_measurement", ...
    'PostEqSINR_dB',39.8,'PostEqSINRSource',"equalizer_measurement", ...
    'PostEqSINRValueStatus',"OK_decision_residual_bounded", ...
    'PostEqSINRRawEqualizer_dB',41,'PostEqSINRDecisionResidualBoundApplied',true, ...
    'PostEqSINRPerLayer_dB',[38 40], ...
    'CFOObservation',struct('ObservationPolicy',"configured_CP_window", ...
    'Status',"measured",'ObservationPairCount',96));
actual=sixgr.phy.ra.receiverDiagnostics(rx);
assert(actual.ReceiverDiagnosticsPresent && actual.EstimatedCFO_Hz==-401.25 && ...
    actual.CFOCPObservationPairCount==96 && actual.RawTimingEstimate_samples==7 && ...
    actual.ResidualCFOReusesAcquisitionObservation==1 && ...
    isnan(actual.ResidualCFO_EstimatedPostCorrection_Hz) && ...
    actual.ResidualCFOEstimatorConsistency_Hz==0 && ...
    actual.ReceiverHestSINR_dB==29.3 && actual.PostEqSINR_dB==39.8 && ...
    actual.PostEqSINRValueStatus=="OK_decision_residual_bounded" && ...
    isequal(jsondecode(actual.PostEqSINRPerLayerJSON),[38;40]));
% Neither failed CRC nor unrelated transmitter/configuration truth may
% erase measured front-end diagnostics or supply a missing receiver value.
rx.TrueCFO_Hz=123456; rx.ConfiguredSNR_dB=99;
rx.Hest=ones(80,14,4,4); rx.Waveform=ones(128,4);
assert(isequaln(actual,sixgr.phy.ra.receiverDiagnostics(rx)));
rx.EstimatedCFO_Hz=0;
assert(sixgr.phy.ra.receiverDiagnostics(rx).EstimatedCFO_Hz==0);
rx.EstimatedCFO_Hz=[1 2];
try
    sixgr.phy.ra.receiverDiagnostics(rx);
catch ex
    assert(strcmp(ex.identifier,'sixgr:ra:ReceiverDiagnosticValue'));
    ok=true; return;
end
error('test:InvalidReceiverDiagnosticAccepted','A scalar CFO field cannot silently accept a vector.');
end

function localCanonicalCommonProcedureMeasurements()
% Deliberately unequal raw/bounded SINR and residual/reference NMSE expose
% mislabeled aliases; this is an adapter fixture, not a waveform claim.
rx=struct('Metrics',struct('MeasuredPostEqualizationSINRdBPerLayer',[18 20], ...
    'PilotReconstructionResidualRatio',0.01,'ChannelEstimateNMSE',0.5, ...
    'FiniteDescrambledLLRCountPerCodeword',100,'DescrambledLLRCountPerCodeword',100, ...
    'LDPCIterationCountPerCodeword',3), ...
    'EffectiveLayerChannelEstimate',ones(4,3,2,2),'EqualizedGrid',ones(4,3,2), ...
    'PostEqSINRRawEqualizerPerLayer_dB',[30 32], ...
    'PostEqSINRDecisionResidualBoundApplied',true, ...
    'TimingEstimateUsed',true,'RawTimingEstimate_samples',7, ...
    'AppliedTimingCorrection_samples',7,'TimingEstimateSource',"received_DMRS", ...
    'EstimatedCFO_Hz',401,'CFOEstimateAvailable',true);
actual=sixgr.pdsch.RASIPDSCHContext.addCompatibilityEvidence(rx);
assert(actual.ReceiverHestSINR_dB==31 && actual.PostEqSINR_dB==19 && ...
    actual.PostEqSINRValueStatus=="OK_DECISION_RESIDUAL_BOUNDED" && ...
    contains(actual.ReceiverHestSINRValueRole,"raw_equalizer") && ...
    actual.ChannelEstimatePilotResidualNMSE_dB==-20 && ...
    actual.Metrics.ChannelEstimateNMSE==0.5 && actual.TimingEstimateUsed && ...
    actual.RawTimingEstimate_samples==7 && actual.AppliedTimingCorrection_samples==7 && ...
    actual.TimingEstimateSource=="received_DMRS" && actual.EstimatedCFO_Hz==401);
rx.Metrics.MeasuredPostEqualizationSINRdBPerLayer=[Inf Inf];
actual=sixgr.pdsch.RASIPDSCHContext.addCompatibilityEvidence(rx);
assert(~actual.PostEqSINRAvailable && isinf(actual.PostEqSINR_dB) && ...
    actual.PostEqSINRValueStatus=="unavailable");
end
