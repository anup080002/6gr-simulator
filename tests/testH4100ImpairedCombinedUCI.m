function ok=testH4100ImpairedCombinedUCI()
% One declared H4 combined-UCI occasion through actual 4x64 CDL/RF.
% The obligation and preconnected spatial state are explicit test boundaries,
% NOT received DCI/CSI/SRS or access evidence. No statistical qualification.
% Receiver allocation is frozen before constructing any transmitted bits.
setup6GRSimToolkit('Verbose',false);
scenario='simulator/configs/scenarios/h4_100_cdlc100_connected_impaired_40db_adaptation.yaml';
source=sixgr.lls6g.config.loadScenarioConfig(scenario);
folder=fullfile(pwd,'results','lls','h4_impaired_combined_uci', ...
    char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
assert(~isfolder(folder),'test:EvidenceExists'); mkdir(folder);
cfg=sixgr.lls6g.buildInternalConfig(source,folder);
cfg=sixgr.truth.attachFixedLinkRuntimeAntennaContext(cfg,1,1);
cfg=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,19);
carrier=sixgr.phy.grid.makeCarrier(cfg);
assert(carrier.NSizeGrid==273 && carrier.SubcarrierSpacing==30 && ...
    cfg.phy.fc_Hz==4e9 && cfg.phy.nTxAnt==64 && cfg.phy.nRxAnt==4);
ue=struct('UEID',1,'RNTI',cfg.phy.pdsch.RNTI,'ServingCell',1, ...
    'PUCCHCell',1,'ComponentCarrier',cfg.phy.frame.DefaultIdentity.ScheduledCCID, ...
    'ActiveULBWP',cfg.phy.frame.DefaultIdentity.ULBWPID);
rrc=sixgr.phy.pucch.PUCCHConfigBuilder.receiverConfiguration(cfg,ue);
installed=sixgr.phy.mimo.CSIReportConfiguration( ...
    cfg.phy.csi.reportConfiguration,cfg.phy.csi.reportConfiguration.Epoch);
obligation=struct('ObservationID',"H4-impaired-combined-component", ...
    'ConfigurationEpoch',rrc.ConfigurationEpoch,'HARQBitCount',2,'SRBitCount',1, ...
    'PriorityIndex',0,'CSIReportConfigID',installed.ReportConfigID, ...
    'CSIConfigurationEpoch',installed.Epoch);
context=sixgr.truth.buildConfiguredPUCCHReceiveContext(obligation,installed);
identity=struct('ObservationID',obligation.ObservationID,'ResourceID',10, ...
    'RNTI',ue.RNTI,'AbsoluteSlot0',18,'Source',"declared_installed_H4_obligation", ...
    'TimingSource',"configured_special_slot",'ResourceSelectionProcedure',"dynamic_harq_csi");
assignment=sixgr.phy.pucch.PUCCHReceptionAssignment(identity,rrc,context);
assert(context.HARQACKBits==2 && context.SRBits==1 && context.CSIPart1Bits==14);
frozenDigest=context.Digest;

request=cfg.phy.csi.reportConfiguration; request.Rank=2;
schema=sixgr.phy.mimo.CSIReportConfiguration(request,request.Epoch);
[~,values]=sixgr.phy.mimo.TypeISinglePanelCodebook.matrix(request,0);
values.RI=2; values.CRI=7; values.CQI_CW0=11;
csi=schema.build(values);
frame=struct('K1',1,'K1Source','declared_component_received_DCI', ...
    'PDSCHEndSlot',18,'TargetSlot',19,'DecodedPRI',0,'PRIFieldWidth',3, ...
    'PRIProvenance','declared_component_received_DCI','FirstCCE',0,'NumCCE',16, ...
    'SlotSymbolOwnership',"DDDDDDDDDDGGUU",'FlexibleResolutionProvided',false);
states=sixgr.truth.initializeConfiguredSRProcedures(cfg,ue);
frame.SchedulingRequestStates=sixgr.phy.pucch.SchedulingRequestState.atSlot(states,18);
plan=sixgr.phy.pucch.PUCCHConfigBuilder.planCombined( ...
    cfg,ue,int8([1;0]),csi.Part1Bits,csi.Part2Bits,frame);
assert(context.Digest==frozenDigest && assignment.Resource.Digest==plan.Plan.Resource.Digest);
% Use the installed configuration's spatial/power authority, not a small-grid
% fixture. This remains an explicitly preconfigured component boundary;
% it is not evidence that access or a spatial-relation MAC command occurred.
materialized=sixgr.phy.pucch.PUCCHConfigBuilder.materialize(cfg,plan);
txAssignment=materialized.Assignment;
tx=sixgr.phy.pucch.PUCCHTransmitter.transmit(carrier,txAssignment,plan.Report);
assert(tx.OFDMInfo.SampleRate==122.88e6 && ...
    tx.OFDMInfo.Nfft==4096 && isnan(tx.Power.AppliedPowerdBm));
scope="actual_H4_CDL_RF_component_declared_control_boundary_not_scenario_or_statistics";
save(fullfile(folder,'configuration.mat'),'source','cfg','scenario','scope', ...
    'obligation','context','assignment','txAssignment');
design=struct('EpisodeID',"H4-combined-independent-H1",'UEIndex',1, ...
    'ServingCell',1,'ChannelSeed',5101361,'NoiseSeed',5101362, ...
    'GuardSamples',256,'SignalPresent',true);
episode=sixgr.link.runIndependentPUCCHReceiverEpisode( ...
    cfg,assignment,context,tx,design,fullfile(folder,'physical'));
rx=episode.Receiver;
first=episode.Clock.RadioStartSample;
assert(episode.Execution.TxDimensions==4 && episode.Execution.RxDimensions==64 && ...
    episode.Execution.DesiredChannelExecuted && episode.ChannelReplay.ChannelFadingApplied);
assert(episode.TXReplay.DACQuantizationApplied && episode.TXReplay.PAApplied && ...
    episode.TXReplay.PhaseNoiseApplied && episode.RXReplay.ADCQuantizationApplied && ...
    episode.RXReplay.PhaseNoiseApplied && episode.RXReplay.TimingOffsetApplied);
assert(all(episode.RFMeasurements.RunId==design.EpisodeID) && ...
    all(startsWith(episode.RFMeasurements.TrialId,design.EpisodeID+"/")) && ...
    all(episode.RFMeasurements.SignalPresent));
assert(rx.IndependentReceiverAssignment && ~rx.PreparedTransmitterConsumed && ...
    ~rx.InjectedNoiseVarianceConsumed && ~rx.InjectedInterferenceCovarianceConsumed && ...
    ~rx.OraclePayloadBitsUsed && ~rx.ReceiveTiming.OracleTimingUsed);
bits=[rx.DecodedFields.HARQACK;rx.DecodedFields.SR; ...
    rx.DecodedFields.CSIPart1;rx.DecodedFields.CSIPart2];
exact=isequal(bits,tx.Serialization.Sequence1.Bits);
row=table(4e9,100,273,4,64,2,1,14,cfg.channel.snr_dB, ...
    rx.DetectionMetric,rx.DetectionThreshold,rx.DTX,rx.CRCApplicable,rx.CRCPassed,exact, ...
    rx.MeasuredSINR_dB,rx.ReceiveTiming.TimingOffsetSamples,false,false,scope, ...
    'VariableNames',{'CarrierHz','BandwidthMHz','NSizeGrid','TxDimensions','RxDimensions', ...
    'HARQBits','SRBits','CSIPart1Bits','ConfiguredSNR_dB','DetectionMetric','DetectionThreshold', ...
    'DTX','CRCApplicable','CRCPassed','ExactDecodedBits','MeasuredSINR_dB','TimingEstimateSamples', ...
    'ScenarioAccepted','StatisticallyQualified','Scope'});
row.RadioStartSample=first;
row.PhysicalEpisodeStartSample=0;
row.RadioMinusPhysicalSampleOffset=first;
row.PrecedingSharedClockHistoryExecuted=false;
sixgr.util.csvWriteTable(fullfile(folder,'received_uci.csv'),row,'PreserveSchema',true);
disp(row);
assert(rx.ReceiverUsable && ~rx.DTX && rx.CRCApplicable && rx.CRCPassed && exact, ...
    'test:H4ImpairedCombinedUCIDecode','Retain the actual failed RF/channel capture; do not tune detector thresholds.');
assert(rx.HARQObservationValid && ~rx.AckObservedValid && ...
    rx.DecodedHARQBitCount==2 && rx.ObservedHARQACKBitCount==1 && ...
    rx.ObservedHARQNACKBitCount==1);
decoded=installed.decode(rx.DecodedFields.CSIPart1,rx.DecodedFields.CSIPart2);
assert(decoded.RI==2 && decoded.PMI==0 && decoded.CRI==7 && decoded.CQI_CW0==11);
assert(episode.Events.CompleteUCIErrorEpisode==0 && ...
    episode.Events.FalseACKBitCount==0 && episode.Events.FalseNACKBitCount==0 && ...
    episode.Events.TXRXFieldLengthsMatch==1 && episode.Events.IndependentWaveformCount==1 && ...
    ~episode.Events.StatisticallyQualified && ...
    isfile(fullfile(folder,'physical','transmitter_reference.mat')));
fprintf('H4_IMPAIRED_COMBINED_UCI_PASS independent_episodes=1 statistical_qualification=0\n');
ok=true;
end
