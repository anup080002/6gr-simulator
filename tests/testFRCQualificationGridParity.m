function ok = testFRCQualificationGridParity()
%TESTFRCQUALIFICATIONGRIDPARITY Guard exact retained-trial reproducibility.
%
% Full qualification uses only required SNR +/- tolerance and the required
% point. This regression compares those retained trials with an explicit
% legacy seven-point sweep and requires identical seeds, outcomes, and
% compact truth evidence.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

if ~localHaveRequired5G()
    ok = true;
    return;
end

frcId = "dl_r_pdsch_1_1_4_fdd_awgn";
conditionId = "awgn_static_1x2";
requiredSNR_dB = 3.2;
legacyOffsets_dB = [-2, -1, -0.5, 0, 0.5, 1, 2];
common = { ...
    "ExecutionProfile", "full", ...
    "MinTransportBlocks", 1, ...
    "MaxTransportBlocks", 1, ...
    "BatchSize", 1, ...
    "Seed", 86420, ...
    "PrintTable", false, ...
    "Verbose", false};

qualified = sixgr.conformance.runFRCPoint( ...
    frcId, conditionId, common{:});
legacy = sixgr.conformance.runFRCPoint( ...
    frcId, conditionId, common{:}, ...
    "SNRGrid_dB", requiredSNR_dB + legacyOffsets_dB);

expectedQualificationGrid = requiredSNR_dB + [-1, 0, 1];
assert(isequal(double(qualified.Sweep.SNR_dB(:).'), ...
    expectedQualificationGrid), ...
    ["The default full FRC sweep must contain only the two prespecified " ...
    "tolerance endpoints and the required point."]);
assert(height(legacy.Sweep) == numel(legacyOffsets_dB), ...
    "An explicit legacy exploratory grid must remain unchanged.");

for index = 1:height(qualified.Sweep)
    snr_dB = double(qualified.Sweep.SNR_dB(index));
    legacyIndex = find(abs(double(legacy.Sweep.SNR_dB) - snr_dB) <= 1e-12, 1);
    assert(~isempty(legacyIndex), ...
        "Retained qualification SNR %.12g dB is absent from the legacy sweep.", ...
        snr_dB);

    qualifiedRow = qualified.Sweep(index, :);
    legacyRow = legacy.Sweep(legacyIndex, :);
    assert(isequaln(qualifiedRow, legacyRow), ...
        ["Qualification-grid pruning changed the exact result row at " ...
        "SNR %.3f dB."], snr_dB);

    qualifiedDetail = qualified.PointDetails{index};
    legacyDetail = legacy.PointDetails{legacyIndex};
    assert(isequaln(qualifiedDetail, legacyDetail), ...
        ["Qualification-grid pruning changed seeds, outcomes, or compact " ...
        "truth evidence at SNR %.3f dB."], snr_dB);
end

assert(~any(qualified.Sweep.ConfidenceQualificationEligible) && ...
    ~qualified.ReferencePointStatisticallyQualified && ...
    ~qualified.StatisticallyQualified, ...
    ["A one-transport-block test override may prove exact grid/seed parity " ...
    "but must never inherit full statistical qualification semantics."]);
assert(qualified.ExecutionBackend == legacy.ExecutionBackend && ...
    qualified.ApproximationMode == "none" && ...
    legacy.ApproximationMode == "none" && ...
    qualified.Source == legacy.Source, ...
    "Grid pruning must not change truth/proxy provenance labels.");
assert(qualified.StandardExecution.NoProxyOrFallbackUsed && ...
    legacy.StandardExecution.NoProxyOrFallbackUsed && ...
    qualified.DataChannelExecution.NoProxyOrFallbackUsed && ...
    legacy.DataChannelExecution.NoProxyOrFallbackUsed, ...
    "Grid pruning must not introduce a proxy or fallback path.");

fprintf("%s\n", ...
    "FRCQualificationGridParity: 7-to-3 full-grid pruning preserves " + ...
    "retained seeds, outcomes, evidence, and truth labels.");
ok = true;
end

function tf = localHaveRequired5G()
tf = exist("nrCarrierConfig", "class") == 8 ...
    && exist("nrPDSCH", "file") == 2 ...
    && exist("nrDLSCHInfo", "file") == 2;
end
