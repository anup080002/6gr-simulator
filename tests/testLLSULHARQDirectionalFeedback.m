function ok = testLLSULHARQDirectionalFeedback()
%TESTLLSULHARQDIRECTIONALFEEDBACK Keep UL HARQ off the PUCCH air interface.

setup6GRSimToolkit("Verbose", false);

rnti = 701;
sourceSlot = 5;
harq = sixgr.l2.mac.HARQEntityUL(struct());
txp = harq.allocate(rnti, sourceSlot, 8, "NewData", true);
harqId0 = double(txp.HARQ.HarqID);
grant = struct( ...
    "Direction", "UL", ...
    "RNTI", rnti, ...
    "TBSBits", 64, ...
    "TBSBytes", 8, ...
    "HARQ", txp.HARQ, ...
    "HARQTBContext", struct("TBId", "UL-701-5-0", "TBSBits", 64));
harq.onTx(rnti, harqId0, zeros(64, 1, "uint8"), grant, sourceSlot);

state = struct( ...
    "ULHarq", harq, ...
    "ULSchedulers", {{}}, ...
    "PendingFeedbackTable", table(), ...
    "PUCCHGrantTraceTable", table());
feedback = struct( ...
    "Direction", "UL", ...
    "RNTI", rnti, ...
    "HarqID", harqId0, ...
    "SourceSlot", sourceSlot, ...
    "DueSlot", sourceSlot + 1, ...
    "ServingCell", 1, ...
    "TBSBits", 64, ...
    "Ack", true, ...
    "Processed", true);

state = sixgr.truth.CoupledTruthRuntime.applyDecodedULHARQOutcomeRuntime( ...
    state, feedback);
assert(double(state.ULHarq.Stats.Ack) == 1 && ...
    double(state.ULHarq.Stats.StaleFeedbackIgnored) == 0, ...
    "The gNB PUSCH decoder outcome must close the matching UL HARQ process.");
assert(isempty(state.PendingFeedbackTable) && isempty(state.PUCCHGrantTraceTable), ...
    ["A decoded UL HARQ outcome must not create pending UE UCI or a " ...
    "PUCCH waveform grant."]);

badTiming = feedback;
badTiming.DueSlot = sourceSlot;
localAssertError(@() sixgr.truth.CoupledTruthRuntime. ...
    applyDecodedULHARQOutcomeRuntime(state, badTiming), ...
    "sixgr:truth:CoupledTruthRuntime:InvalidULHARQDecoderTiming");
badDirection = feedback;
badDirection.Direction = "DL";
localAssertError(@() sixgr.truth.CoupledTruthRuntime. ...
    applyDecodedULHARQOutcomeRuntime(state, badDirection), ...
    "sixgr:truth:CoupledTruthRuntime:InvalidULHARQOutcomeDirection");

ok = true;
fprintf("testLLSULHARQDirectionalFeedback: PASS\n");
end

function localAssertError(f, expectedId)
threw = false;
try
    f();
catch ME
    threw = true;
    assert(strcmp(string(ME.identifier), string(expectedId)), ...
        "Expected %s, received %s.", expectedId, ME.identifier);
end
assert(threw, "Expected typed error %s.", expectedId);
end
