function ok = testAWGNAntennaChannelConsistency()
%TESTAWGNANTENNACHANNELCONSISTENCY Qualify explicit AWGN antenna semantics.

setup6GRSimToolkit("Verbose", false);
root = tempname;
mkdir(root);
cleanup = onCleanup(@() localCleanup(root)); %#ok<NASGU>

cfg = sixgr.config.defaultConfig();
cfg.channel.model = "AWGN";
cfg.channel.awgnOnly = true;
cfg.channel.pathlossEnabled = false;
cfg.channel.shadowFadingEnabled = false;
cfg.channel.sharedIdentityAWGNEnabled = true;
cfg.meta.configHash = "awgn_antenna_consistency_unit";
cfg.run.id = "awgn_antenna_consistency_unit";

dl = localTrial("DL", 4, 4);
ul = localTrial("UL", 4, 4);
runFolder = fullfile(root, "pass");
artifacts = sixgr.truth.exportLLSLiveDerivedTables(cfg, runFolder, ...
    struct("DL", dl, "UL", ul), struct(), struct(), struct());
T = readtable(char(artifacts.AntennaRuntimeEvidencePath), ...
    "VariableNamingRule", "preserve", "Delimiter", ",");
assert(height(T) == 2 && all(logical(T.AntennaChannelConsistencyOk)), ...
    "Dimensionally consistent identity-AWGN DL/UL rows must pass antenna/channel consistency.");
assert(all(strcmpi(string(T.ElementPatternChannelApplicability), ...
    "not_applicable_awgn_identity_channel")) && ...
    all(strcmpi(string(T.AntennaChannelConsistencyStatus), ...
    "pass_not_applicable_awgn_identity_channel")), ...
    "AWGN rows must carry an explicit not-applicable element-pattern classification.");
assert(all(~logical(T.ChannelUsesCountOnlyAntennaModel)) && ...
    all(~logical(T.ChannelUsesSameRuntimeAntennaAssumptions)) && ...
    all(~logical(T.TransmitElementPatternApplied)) && ...
    all(~logical(T.ReceiveElementPatternApplied)), ...
    "AWGN rows must not claim count-only spatial handling, shared array assumptions, or applied patterns.");
assert(all(strcmpi(string(T.ChannelObjectSource), ...
    "sixgr.channel.IdentityAWGNRuntime.materialize")) && ...
    all(strcmpi(string(T.ChannelObjectClass), ...
    "explicit_identity_sample_operator")), ...
    "AWGN rows must identify the executed identity sample operator.");

layout = sixgr.report.resultLayout(runFolder);
profileT = table(1, string(fullfile(pwd, "+sixgr", "+channel", ...
    "ChannelFactory.m")), 2, 0.01, ...
    'VariableNames', {'ProfileRank','FileName','NumCalls','TotalTime_s'});
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, ...
    "runtime_function_profile.csv"), profileT);
stage = localStage();
auditCfg = struct("enabled", true, "required", true, ...
    "fail_on_enabled_bypass", true, "stages", stage, ...
    "parameter_bindings", struct([]));
scfg = struct("validation", struct("causal_phy_chain_audit", auditCfg));
cfg.validation.causal_phy_chain_audit = auditCfg;
audit = sixgr.truth.exportCausalPHYChainAudit(runFolder, scfg, cfg, ...
    "RunId", "awgn_antenna_consistency_unit", "WriteArtifacts", false);
assert(audit.Ok && audit.DetailTable.StageOutcome == "PASS", ...
    "The causal antenna/channel stage must accept honest AWGN non-applicability evidence.");

badDL = localTrial("DL", 4, 3);
badFolder = fullfile(root, "dimension_mismatch");
badArtifacts = sixgr.truth.exportLLSLiveDerivedTables(cfg, badFolder, ...
    struct("DL", badDL, "UL", ul), struct(), struct(), struct());
badT = readtable(char(badArtifacts.AntennaRuntimeEvidencePath), ...
    "VariableNamingRule", "preserve", "Delimiter", ",");
badRow = strcmpi(string(badT.Direction), "DL");
assert(sum(badRow) == 1 && ~logical(badT.AntennaChannelConsistencyOk(badRow)) && ...
    strcmpi(string(badT.AntennaChannelConsistencyStatus(badRow)), ...
    "fail_awgn_runtime_dimension_mismatch"), ...
    "AWGN classification must fail closed when observed receive dimensions disagree with configuration.");

ok = true;
fprintf('AWGN_ANTENNA_CHANNEL_CONSISTENCY_PASS rows=%d negative=dimension_mismatch\n', height(T));
end

