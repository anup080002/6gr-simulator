function ok=testSLSCoreFTP3LoadCalibration()
% Generic SLS contract fixtures; no row here is a physical study result.
baseHash=string(repmat('b',1,64));
cases=table(["case_a";"case_b"],["drop_a";"drop_b"], ...
    ["population_1";"population_1"],["baseline";"baseline"], ...
    [50;50],{localSeeds(11);localSeeds(23)}, ...
    repmat(baseHash,2,1),repmat("waveform",2,1),repmat("",2,1), ...
    'VariableNames',{'CaseID','IndependentDropID','PopulationID', ...
    'CalibrationRole','TargetRUPercent','SeedBundle','BaseConfigSHA256', ...
    'PlannedExecutionArchitecture','LinkCalibrationSHA256'});
policy=struct('initial_arrival_rate_per_cell_s',1, ...
    'maximum_arrival_rate_per_cell_s',8,'bracket_expansion_factor',2, ...
    'maximum_iterations',5,'tolerance_percentage_points',0.01, ...
    'minimum_independent_drops',2,'warmup_tti',0, ...
    'measurement_direction',"UL");
folder=string(tempname);
cleanup=onCleanup(@()localRemove(folder));
out=sixgr.system.calibrateFTP3Loads(cases,policy,@localExecute,folder);
assert(out.Ok && out.LoadConverged && ~out.PrimaryStudyAccepted && ...
    height(out.Rates)==1 && out.Rates.ArrivalRatePerCell_s==2 && ...
    out.Rates.MeasuredRUPercent==50 && height(out.Iterations)==2);
assert(isfile(fullfile(folder,"frozen_ftp3_rates.csv")) && ...
    isfile(fullfile(folder,"load_calibration_plan.mat")) && ...
    isfile(fullfile(folder,out.Rates.CalibrationKey(1), ...
    'iteration_002','drop_001','runtime_result.mat')));
localReject(@()sixgr.system.calibrateFTP3Loads(cases,policy,@localExecute,folder), ...
    'sixgr:system:FTPLoadPlan');
resumed=sixgr.system.calibrateFTP3Loads(cases,policy,@localExecute,folder,'Resume',true);
assert(isequaln(out.Rates,resumed.Rates) && isequaln(out.Iterations,resumed.Iterations), ...
    'Resume must rebuild identical totals without reexecuting sealed drops.');
changedPolicy=policy; changedPolicy.maximum_iterations=6;
localReject(@()sixgr.system.calibrateFTP3Loads(cases,changedPolicy,@localExecute,folder,'Resume',true), ...
    'sixgr:system:FTPLoadResumeIdentity');
interrupted=fullfile(folder,'interrupted');
localReject(@()sixgr.system.calibrateFTP3Loads(cases,policy,@localInterrupt,interrupted), ...
    'test:S0Interrupted');
allow=true; save(fullfile(interrupted,'allow_resume.mat'),'allow');
recovered=sixgr.system.calibrateFTP3Loads(cases,policy,@localInterrupt,interrupted,'Resume',true);
assert(isequaln(out.Rates,recovered.Rates) && isequaln(out.Iterations,recovered.Iterations), ...
    'An interrupted drop must resume with the original seeds, bracket and retained completed drops.');
resultFile=fullfile(interrupted,recovered.Rates.CalibrationKey(1), ...
    'iteration_001','drop_001','runtime_result.mat');
tampered=load(resultFile,'result'); result=tampered.result;
result.Details.TrafficArrivalRatePerCell_s=999;
save(resultFile,'result');
localReject(@()sixgr.system.calibrateFTP3Loads(cases,policy,@localInterrupt,interrupted,'Resume',true), ...
    'sixgr:system:FTPLoadResumeDigest');
bad=cases; bad.SeedBundle{2}=bad.SeedBundle{1};
localReject(@()sixgr.system.calibrateFTP3Loads(bad,policy,@localExecute, ...
    fullfile(folder,"duplicate_seeds")),'sixgr:system:FTPLoadDrops');
assert(~isfolder(fullfile(folder,"duplicate_seeds")), ...
    'Invalid independent-drop plans must not create a partial run folder.');
bad=cases; bad.SeedBundle{2}=rmfield(bad.SeedBundle{2},'PropagationSeed');
localReject(@()sixgr.system.calibrateFTP3Loads(bad,policy,@localExecute, ...
    fullfile(folder,"missing_seed")),'sixgr:system:FTPLoadSeeds');
bad=cases; bad.CalibrationRole(2)="comparator";
localReject(@()sixgr.system.calibrateFTP3Loads(bad,policy,@localExecute, ...
    fullfile(folder,"comparator")),'sixgr:system:FTPLoadPlan');
localReject(@()sixgr.system.calibrateFTP3Loads(cases,policy,@localWrongConfig, ...
    fullfile(folder,"wrong_config")),'sixgr:system:FTPLoadIdentity');
assert(isfile(fullfile(folder,"wrong_config", ...
    "load_calibration_plan.mat")) && ...
    ~isempty(dir(fullfile(folder,"wrong_config","**","failure.mat"))));
ok=true;
fprintf('SLS_CORE_FTP3_LOAD_CALIBRATION_PASS fixture_only=1\n');
end

function seeds=localSeeds(base)
seeds=struct('GeometrySeed',base,'ShadowSeed',base+1, ...
    'TrafficSeed',base+2,'AntennaOrientationSeed',base+3, ...
    'SchedulerSeed',base+4,'PropagationSeed',base+5);
end

function result=localExecute(request)
% This callback produces a contract fixture in a private temporary folder.
marker=fullfile(request.OutputFolder,'fixture_callback_executed.mat');
assert(~isfile(marker),'test:DuplicateDropExecution', ...
    'A sealed drop must not execute again during resume.');
executed=true; save(marker,'executed');
n=round(2*request.ArrivalRatePerCell_s);
grant=table(1,1,"UL",string(jsonencode(0:n-1)),0,1,32, ...
    "measured","OK",true,false,"","","", ...
    'VariableNames',{'TTI','CellID','Direction','PRBSet','SymbolStart', ...
    'NumSymbols','TBSBits','PHYDecisionRole','PHYDecisionStatus', ...
    'WaveformReplayExecuted','CalibrationQualified','CalibrationSHA256', ...
    'CalibrationKeySHA256','SourceClassification'});
opportunity=table(1,1,"UL",string(jsonencode(0:7)),0,1, ...
    "executed_slot_scheduler_budget_independent_of_grants", ...
    'VariableNames',{'TTI','CellID','Direction','PRBSet','SymbolStart', ...
    'NumSymbols','Source'});
details=struct('WaveformBacked',true,'ProxyPHYActive',false, ...
    'FallbackUsed',false,'SeedBundle',request.Case.SeedBundle{1}, ...
    'SchedulerGrants',grant,'ResourceOpportunityTable',opportunity, ...
    'TrafficArrivalEvents',localArrivals(), ...
    'TrafficArrivalStreamID',"fixture_ftp3_stream", ...
    'TrafficDefinitionSource', ...
        "configured_fixed_file_continuous_time_poisson_ftp3", ...
    'TrafficDeterministic',true, ...
    'TrafficModel',"ftp3", ...
    'TrafficArrivalRatePerCell_s',request.ArrivalRatePerCell_s, ...
    'LoadCalibrationBaseConfigSHA256', ...
    string(request.Case.BaseConfigSHA256(1)), ...
    'DecodeUnavailableUL',0);
result=struct('Ok',true,'Details',details);
end

function result=localInterrupt(request)
root=fileparts(fileparts(fileparts(request.OutputFolder)));
if string(request.Case.CaseID)=="case_b" && ~isfile(fullfile(root,'allow_resume.mat'))
    error('test:S0Interrupted','Intentional interruption after the first retained drop.');
end
result=localExecute(request);
end

function T=localArrivals()
T=table("fixture_arrival_1",1,0.01,1,100,800,"UL",11, ...
    "fixture_ftp3_stream","fixed_file_continuous_time_poisson", ...
    'VariableNames',{'ArrivalID','ArrivalTTI','ArrivalTime_s','UEID', ...
    'FileSizeBytes','OfferedBits','Direction','Seed','ArrivalStreamID', ...
    'ArrivalProcess'});
end

function result=localWrongConfig(request)
result=localExecute(request);
result.Details.LoadCalibrationBaseConfigSHA256=string(repmat('c',1,64));
end

function localReject(action,id)
try
    action();
catch ME
    assert(string(ME.identifier)==string(id), ...
        'Expected %s, got %s: %s',id,ME.identifier,ME.message);
    return
end
error('test:MissingRejection','Expected %s.',id);
end

function localRemove(folder)
if isfolder(folder), rmdir(folder,'s'); end
end
