function ok = testStandaloneControlSweepSNRBinding()
%TESTSTANDALONECONTROLSWEEPSNRBINDING Guard PBCH sweep stimulus binding.

cfg = struct("channel", struct("snr_dB", 99, "model", "AWGN"));
for snr_dB = [-20, 0, 20]
    pointCfg = sixgr.truth.bindStandaloneSNRPoint(cfg, snr_dB);
    assert(double(pointCfg.channel.snr_dB) == snr_dB, ...
        "Standalone waveform configuration did not receive the sweep SNR.");
    assert(string(pointCfg.channel.model) == "AWGN", ...
        "Binding a standalone SNR point must preserve other channel fields.");
end
assert(double(cfg.channel.snr_dB) == 99, ...
    "Binding a standalone SNR point must not mutate the source configuration.");

cfg.run.seed = 104729;
trial1 = sixgr.truth.bindStandalonePBCHTrial(cfg, -20, 1, 0);
trial2 = sixgr.truth.bindStandalonePBCHTrial(cfg, -20, 2, 3);
assert(double(trial1.run.seed) == 104729 && double(trial2.run.seed) == 104730, ...
    "Standalone PBCH trials must use distinct deterministic seeds.");
assert(double(trial1.phy.ssb.runtimeSSBIndex) == 0 && ...
    double(trial2.phy.ssb.runtimeSSBIndex) == 3, ...
    "Standalone PBCH trials must materialize the selected SSB index.");
assert(double(trial1.channel.snr_dB) == -20 && ...
    double(trial2.channel.snr_dB) == -20, ...
    "Standalone PBCH trial binding must retain the operating-point SNR.");

source = fileread(which("sixgr.truth.runWaveformLinkBundle"));
assert(contains(source, "runCellSearch_MIB_SIB1(cfgTrial"), ...
    "PBCH standalone trials must execute with the fully bound trial configuration.");
assert(contains(source, "cfgTrial = sixgr.truth.bindStandalonePBCHTrial"), ...
    "PBCH standalone trials must bind SNR, seed, and SSB index before waveform execution.");
assert(contains(source, "pointT = pointT(isfinite(configured)"), ...
    "Live SNR metrics must be reduced from the current operating point, not cumulative rows.");

timingSource = fileread(which("sixgr.phy.sync.timingEstimate"));
assert(~contains(timingSource, "warning('sixgr:sync:BadTimingEstimate'"), ...
    "Recoverable SSB timing clipping must not depend on a writable warning stream.");
assert(contains(timingSource, "sixgr.util.safeFprintf(2"), ...
    "Recoverable SSB timing diagnostics must use fail-safe console output.");
assert(contains(timingSource, "ceil(5e-3 * double(sampleRateHz))"), ...
    "Frame-aligned simulator SSB timing must search the canonical first half-frame.");

ssbTiming = sixgr.phy.frame.SSBTimingResolver.resolve( ...
    "Case", "B", "CarrierFrequencyHz", 4e9, ...
    "FrequencyRange", "FR1", "Lmax", 8);
widebandPSS = sixgr.phy.sync.buildPSSCorrelationReference( ...
    ssbTiming, 0, 122.88e6, "CandidateStartSymbol", 4);
assert(numel(widebandPSS) > 2048 && any(abs(widebandPSS) > 0), ...
    "The 100 MHz PSS correlation reference must include its active OFDM symbol.");
slotZeroPSS = sixgr.phy.sync.buildPSSCorrelationReference( ...
    ssbTiming, 0, 122.88e6, "CandidateStartSymbol", 0);
assert(numel(widebandPSS) ~= numel(slotZeroPSS), ...
    "PSS references must preserve candidate-symbol cyclic-prefix timing.");
freqSource = fileread(which("sixgr.phy.sync.freqOffsetCorrect"));
assert(~contains(freqSource, "w(1:min(end, 2048))"), ...
    "PSS frequency search must not truncate a wideband reference before its active symbol.");
assert(contains(freqSource, "repmat(subframeSymbolLengths, 1, 5)"), ...
    "Frame-aligned PSS/CFO search must retain an explicit half-frame bound.");
assert(contains(freqSource, "localSSBCandidateSearchSegments"), ...
    "PSS/CFO search must evaluate only canonical SS/PBCH candidate windows.");
assert(contains(freqSource, "TimingSearchGuardSamples"), ...
    "PSS candidate correlation must honor the configured timing-uncertainty guard.");
assert(contains(freqSource, "SelectedTimingOffsetSamples"), ...
    "Blind PSS search must export the winning candidate correlation lag as timing evidence.");
assert(contains(freqSource, "SelectedCandidateStartSymbol"), ...
    "Blind PSS search must export the candidate symbol needed for exact CP demodulation.");
assert(contains(freqSource, "normalisedCorrelation = c ./ denominator"), ...
    "PSS candidate ranking must use energy-normalised correlation across unequal-energy windows.");
assert(contains(freqSource, "useBatchMex = false"), ...
    "The truth PSS path must not use the legacy unnormalised correlation kernel.");
ssbRxSource = fileread(which("sixgr.phy.dl.SSB_Rx"));
assert(contains(ssbRxSource, "blind_pss_candidate_window_correlation"), ...
    "SSB reception must reuse blind PSS candidate timing instead of a broad PDSCH-contaminated search.");
assert(contains(ssbRxSource, "symbolWithinSlot + (1:4)"), ...
    "SSB reception must demodulate and extract the block at its canonical within-slot symbols.");

configuredCfg = struct("run", struct( ...
    "noiseOperatingMode", "standalone_awgn_snr_argument"));
[configuredReplaySNR, configuredReplay] = ...
    sixgr.truth.resolveCoupledReplaySNR(configuredCfg, 20);
assert(configuredReplay && configuredReplaySNR == 20, ...
    "Configured AWGN coupled control/data trials must retain the requested sweep point.");

thermalCfg = struct("run", struct( ...
    "noiseOperatingMode", "receiver_noise_figure_thermal_noise"));
[thermalReplaySNR, configuredReplay] = ...
    sixgr.truth.resolveCoupledReplaySNR(thermalCfg, 20);
assert(~configuredReplay && isnan(thermalReplaySNR), ...
    "Receiver-noise geometry mode must continue to require measured runtime link quality.");

ok = true;
fprintf("[PASS] Standalone PBCH sweep SNR binding\n");
end
