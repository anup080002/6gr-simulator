function ok = testSIB1RuntimeFadingMultiPort()
%TESTSIB1RUNTIMEFADINGMULTIPORT Keep SIB1 on the configured physical chain.

setup6GRSimToolkit("Verbose", false);
if exist("nrWaveformGenerator", "file") ~= 2
    ok = true;
    return;
end

root = fileparts(fileparts(mfilename("fullpath")));
scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile(root, ...
    "simulator", "configs", "scenarios", ...
    "webgui_sinr_sweep_64x4_mu_mimo_repair_slice.yaml"));
runRoot = fullfile(tempdir, "sixgr_sib1_runtime_fading_multiport");
cfg = sixgr.lls6g.buildInternalConfig(scenario, runRoot);
assert(sixgr.channel.resolveConcreteProfile(cfg) ~= "AWGN", ...
    "This regression requires the configured fading-channel path.");

multiUser = struct("Enabled", true, "NumUsers", 4, ...
    "RNTIStart", 1, "SeedStride", 17, ...
    "ExecutionModel", "slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfg, runRoot, multiUser, struct(), 20);
state = sixgr.truth.CoupledTruthRuntime.advanceFrame( ...
    state, cfg, multiUser, 1, 20);
state = sixgr.truth.CoupledTruthRuntime.startSlot( ...
    state, cfg, "DL", 1, 1, 1, 20, 20);
[cfgUE, state] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
    cfg, state, 1, "DL");
[state, channelState] = ... %#ok<ASGLU>
    sixgr.truth.CoupledTruthRuntime.acquireRuntimeChannelStateForControl( ...
    state, cfgUE, 1, "DL");
cfgTrial = sixgr.truth.bindStandalonePBCHTrial(cfgUE, 20, 1, 0);

result = sixgr.link.runCellSearch_MIB_SIB1(cfgTrial, ...
    "NumSubframes", 20, "SSBIndex", 0, ...
    "WriteArtifacts", false, "UseRuntimeChannel", true, ...
    "InitialDLChannelState", channelState, "RuntimeSlot", 1);
replay = result.RuntimeChannelReplay;

assert(logical(result.RuntimeChannelStateUsed) && ...
    logical(sixgr.util.structGet(replay, ...
        "RuntimeChannelElementExpansionApplied", false)) && ...
    double(sixgr.util.structGet(replay, ...
        "RuntimeChannelPhysicalTxElements", NaN)) == 64, ...
    "SIB1 must traverse the persistent 64-element gNB channel path.");
assert(logical(result.PBCH.Ok) && logical(result.SIB1.DCICrcPass) && ...
    logical(result.SIB1.DLSCHCrcPass) && ...
    logical(result.SIB1.SIB1ASN1DecodeOk) && ...
    logical(result.SIB1.SIB1TreeEqual) && logical(result.Ok), ...
    "The same fading waveform must pass PBCH, DCI, DL-SCH, and SIB1 semantics: %s", ...
    string(result.SIB1.FailureReason));
assert(logical(result.StrictReceiverEvidenceOk) && ...
    logical(result.SIB1PDSCHStrictReceiverEvidenceOk) && ...
    isfinite(double(result.ReceiverHestSINR_dB)) && ...
    isfinite(double(result.SIB1PDSCHReceiverHestSINR_dB)), ...
    "PBCH and SIB1 must both expose measured receiver evidence.");
ok = true;
end
