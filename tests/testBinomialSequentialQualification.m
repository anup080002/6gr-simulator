function ok = testBinomialSequentialQualification()
%TESTBINOMIALSEQUENTIALQUALIFICATION Exact, fail-closed stopping guards.

setup6GRSimToolkit("Verbose", false);

common = {"ConfidenceLevel",0.95,"MinimumTrials",300, ...
    "MaximumTrials",3000,"MinimumEvents",0,"CIWidthTarget",0.01, ...
    "LookIndex",1,"PlannedLooks",10,"MetricName","false_alarm_probability"};

small = sixgr.stats.evaluateBinomialStopping(0,69,0.01,common{:});
assert(small.Qualification == "NOT_EVALUATED" && ~small.StatisticallyQualified, ...
    "A zero-event point estimate with too few decisions must not pass.");
assert(small.CIUpper > small.TargetProbability, ...
    "The exact upper bound must expose the uncertainty hidden by 0/N.");

tiny = sixgr.stats.evaluateBinomialStopping(0,3,0.001, ...
    "ConfidenceLevel",0.95,"MinimumTrials",3,"MaximumTrials",3000, ...
    "MinimumEvents",0,"CIWidthTarget",0.001,"LookIndex",1, ...
    "PlannedLooks",10,"MetricName","prach_false_alarm_probability");
assert(tiny.PointEstimatePass && tiny.Qualification == "NOT_EVALUATED", ...
    "PointEstimatePass is informational and must not grant qualification.");

enough = sixgr.stats.evaluateBinomialStopping(0,3000,0.01, ...
    "ConfidenceLevel",0.95,"MinimumTrials",300,"MaximumTrials",3000, ...
    "MinimumEvents",0,"CIWidthTarget",0.01,"LookIndex",1, ...
    "PlannedLooks",1,"FinalLook",true,"MetricName","false_alarm_probability");
assert(enough.Qualification == "PASS" && enough.CIUpper <= enough.TargetProbability, ...
    "A zero-event campaign may pass only when its exact upper bound proves the target.");

bad = sixgr.stats.evaluateBinomialStopping(80,300,0.01, ...
    "ConfidenceLevel",0.95,"MinimumTrials",300,"MaximumTrials",300, ...
    "MinimumEvents",0,"CIWidthTarget",0.2,"LookIndex",1, ...
    "PlannedLooks",1,"FinalLook",true,"MetricName","false_alarm_probability");
assert(bad.Qualification == "FAIL" && bad.CILower > bad.TargetProbability, ...
    "A lower confidence bound above target must fail loudly.");

fixed = sixgr.stats.evaluateBinomialStopping(0,300,0.01, ...
    "ConfidenceLevel",0.95,"MinimumTrials",300,"MaximumTrials",300, ...
    "MinimumEvents",0,"CIWidthTarget",0.1,"LookIndex",1, ...
    "PlannedLooks",1,"FinalLook",true);
sequential = sixgr.stats.evaluateBinomialStopping(0,300,0.01, ...
    "ConfidenceLevel",0.95,"MinimumTrials",300,"MaximumTrials",300, ...
    "MinimumEvents",0,"CIWidthTarget",0.1,"LookIndex",1, ...
    "PlannedLooks",20,"FinalLook",true);
assert(sequential.EffectiveDirectionalConfidenceLevel > fixed.EffectiveDirectionalConfidenceLevel && ...
    sequential.CIUpper > fixed.CIUpper, ...
    "A planned sequential campaign must spend less alpha per look than a fixed sample.");

try
    sixgr.stats.evaluateBinomialStopping(4,3,0.01,common{:});
    error("sixgr:test:ExpectedInvalidCounts", "Expected invalid binomial counts to fail.");
catch ME
    assert(string(ME.identifier) == "sixgr:validation:InvalidBinomialCounts", ...
        "Invalid counts must retain the typed validation error.");
end

ok = true;
end
