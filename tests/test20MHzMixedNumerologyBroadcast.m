function ok=test20MHzMixedNumerologyBroadcast()
% Actual SS30/common15 PBCH decoding. Isolated wired channel, not CDL qualification.
setup6GRSimToolkit('Verbose',false);
s=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/validation/lls_n40_ssb30_common15_regression.yaml');
cfg=sixgr.lls6g.buildInternalConfig(s,tempname);
[bound,contract]=sixgr.rf.resolveSSBPowerContract(cfg);
[again,repeated]=sixgr.rf.resolveSSBPowerContract(bound);
assert(isequaln(bound,again) && isequaln(contract,repeated));
assert(contract.FixedSNRNormalizedReference && ~contract.PhysicalDevicePowerClaim && ...
    contract.OFDMUnitReference.Nfft==2048 && contract.OFDMUnitReference.SSBNfft==1024);
[wave,~,tx]=sixgr.phy.dl.SSB_Tx(cfg,'NumSubframes',2);
assert(size(wave,2)==64 && tx.SampleRate_Hz==30.72e6 && ...
    tx.SubcarrierSpacing_kHz==15 && tx.SSB.SCS_kHz==30 && ...
    string(tx.SSB.BlockPattern)=="Case C");
% A declared single wired TX observation avoids geometry/oracle selection.
% All four transmitted beams have a nonzero first physical-element weight.
received=wave(:,1);
[grid,sync]=sixgr.phy.dl.SSB_Rx(received,cfg,'SampleRate_Hz',tx.SampleRate_Hz);
[pb,info]=sixgr.phy.dl.PBCH_Recovery(grid,sync,cfg);
assert(pb.Ok && pb.PDCCHConfigSIB1==cfg.phy.mib.pdcchConfigSIB1);
bits=info.Selected.trblk;
mib=sixgr.phy.broadcast.decodeMIBTransportBlock(bits);
assert(mib.SubCarrierSpacingCommonBit==0, ...
    'MIB must advertise common SCS 15 kHz, not the 30-kHz SSB SCS.');
% Independent exact TX power check on the selected generated SS burst.
[allPorts,txSync]=sixgr.phy.dl.SSB_Rx(wave,cfg, ...
    'SampleRate_Hz',tx.SampleRate_Hz,'CandidateSSBIndex',pb.MIBSSBIndex);
symbols=reshape(allPorts,960,[]);
sss=double(symbols(nrSSSIndices,:))/double(txSync.Nfft);
powerDB=10*log10(mean(sum(abs(sss).^2,2)));
assert(abs(powerDB-contract.NormalizedWaveformEPRE_dB_re_UnitOccupiedRE_Es)<1e-6, ...
    'Mixed-numerology generated SSS power %.12g differs from contract %.12g.', ...
    powerDB,contract.NormalizedWaveformEPRE_dB_re_UnitOccupiedRE_Es);
clear wave allPorts received grid symbols sss
% Exercise the actual Type-0/SIB1 common-SCS chain, not only the MIB bit.
prepared=sixgr.link.prepareCellSearchBroadcast(cfg,true);
assert(prepared.PowerContext.FixedSNRNormalizedReference && ...
    ~prepared.PowerContext.PhysicalDevicePowerClaim && ...
    ~prepared.PowerContext.ScaleApplied && prepared.PowerContext.AmplitudeScale==1 && ...
    string(prepared.PowerContext.PowerNormalizationPolicy)=="unit_occupied_re_fixed_esn0");
assert(isequal(prepared.TransmitSamples,prepared.Tx.Waveform), ...
    'Normalized preparation must preserve actual emitted samples exactly.');
assert(~isfield(prepared.TxInfo,'PortGrid') && ...
    prepared.TxInfo.SSBSubcarrierSpacingKHz==30 && ...
    prepared.TxInfo.CommonSubcarrierSpacingKHz==15 && ...
    ~isempty(prepared.Tx.SSBWaveInfo.SSBComposite.TransmitPortResourceGrid) && ...
    all(arrayfun(@(p)~isempty(p.SIB1Grid),prepared.Tx.SIB1Transmissions)), ...
    'Retain native producer grids; never claim a mixed waveform has one common-SCS RE grid.');
% This change must not silently admit an unqualified absolute-power path.
absolute=cfg; absolute.integration.configured_snr_is_link_authority=false;
try
    sixgr.rf.resolveSSBPowerContract(absolute);
    error('test20MHzMixedNumerologyBroadcast:MissingAbsolutePowerGuard', ...
        'Absolute mixed-numerology power still requires independent qualification.');
catch e
    assert(string(e.identifier)=="sixgr:rf:SSBMixedNumerologyPowerUnqualified",e.message);
end
decoded=sixgr.phy.broadcast.recoverSIB1FromWaveform( ...
    prepared.TransmitSamples(:,1),prepared.ReceiverConfig, ...
    'CandidateSSBIndex',0);
assert(decoded.DLSCHCrcPass && decoded.SIB1ASN1DecodeOk && ...
    decoded.DCIBlindDecodeSuccess && isempty(decoded.UsedOracleFields), ...
    'Mixed SS30/common15 must decode real SI-RNTI DCI and SIB1 without TX oracle.');
[ue,~]=sixgr.mac.ra.installDecodedSIB1RACHConfig(cfg,decoded);
assert(ue.random_access.ss_pbch_block_power_dbm==contract.SSPBCHBlockPower_dBm);
ok=true; disp('MIXED_SSB30_COMMON15_PBCH_DECODE_PASS');
end
