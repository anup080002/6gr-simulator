function folder=diagnoseH4RetainedCSIGrantHandoff(evidenceFolder,folder)
% Replay actual received CSI into future H4 grants and decoded control.
% This is a component replay, not a continuation of the original channel.
% PDCCH uses a declared noiseless logical-port link; PDSCH TX is executed.
% Access, CDL/RF data reception, BLER and full-scenario acceptance are NOT
% qualified here. Never copy these rows into primary scenario trial tables.
setup6GRSimToolkit('Verbose',false);
if nargin<2
    folder=fullfile(pwd,'results','diagnostics','h4_received_csi_grant', ...
        char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')));
end
assert(~isfolder(folder),'test:EvidenceExists','Preserve prior replay evidence.');
configurationFile=fullfile(evidenceFolder,'configuration.mat');
receivedFile=fullfile(evidenceFolder,'received_evidence.mat');
configuration=load(configurationFile,'cfg','scope');
retained=load(receivedFile,'received','feedback','feedbackByReport','adaptationByReport');
cfg=configuration.cfg;
assert(cfg.phy.fc_Hz==4e9 && cfg.phy.carrier.NSizeGrid==273 && ...
    cfg.phy.nTxAnt==64 && cfg.phy.nRxAnt==4);
reports=retained.received;
assert(height(reports)==cfg.phy.linkAdaptation.rankIncreaseConfirmationReports && ...
    all(reports.CSIUCIDecodeOk) && all(reports.SourceSignal=="received_CSI_UCI") && ...
    all(reports.CSIUCITransport=="pucch_independently_received"));
assert(reports.SchedulerSpatialDecisionDeferred(1) && ...
    ~retained.feedbackByReport{1}.Valid && ...
    ~reports.SchedulerSpatialDecisionDeferred(end) && retained.feedback.Valid);
assert(all(isnan(reports.SINR_dB)) && isnan(retained.feedback.SINR_dB), ...
    'Do not substitute UE-side measured SINR for a non-transmitted CSI field.');
mkdir(folder);
receipt=struct('Scope',"retained_physical_UCI_replay_to_grant_unit_PDCCH_and_PDSCH_TX", ...
    'InputFolder',string(evidenceFolder), ...
    'InputSHA256',[string(sixgr.util.sha256File(configurationFile)), ...
        string(sixgr.util.sha256File(receivedFile))], ...
    'AccessExecuted',false,'SharedChannelContinued',false, ...
    'DataReceiverQualified',false,'ScenarioAccepted',false, ...
    'Completed',false,'Ok',false);
sources=["+sixgr/+truth/CoupledTruthRuntime.m", ...
    "+sixgr/+l2/+mac/SchedulerBase.m","+sixgr/+phy/+dl/PDSCH_Tx.m", ...
    "+sixgr/+phy/+dl/PDCCH_Rx.m","tests/diagnoseH4RetainedCSIGrantHandoff.m"];
receipt.SourceFiles=sources;
receipt.SourceSHA256=arrayfun(@(p)string(sixgr.util.sha256File(p)),sources);
sixgr.util.jsonWrite(fullfile(folder,'receipt.json'),receipt);
try
    multi=struct('Enabled',true,'NumUsers',1,'RNTIStart',1, ...
        'ExecutionModel','slot_coupled_truth');
    % Replay only the measured feedback boundary, not fabricated RA/TRS
    % evidence or an artificial scheduler eligibility override.
    state=sixgr.truth.CoupledTruthRuntime.initialize( ...
        cfg,folder,multi,struct(),double(reports.DeliveredSlot(end))+20);
    state.CurrentServingIdx(:)=1;
    state.LatestDLFeedback=retained.feedback;
    state.DLLinkAdaptationState{1}=retained.adaptationByReport{end};
    state.BeamManagementMachines{1}=sixgr.phy.beam.BeamManagementStateMachine('TCI_PENDING');
    state.CurrentSlot=double(reports.DeliveredSlot(end));
    state=sixgr.truth.CoupledTruthRuntime.stageReceivedCSIBeamRuntime( ...
        state,table2struct(reports(end,:)));
    assert(isnan(state.ActiveTCIStateIDByUE(1)));
    rows=table(); frozenBefore=[];
    firstSlot=state.CurrentSlot+1;
    % Bound the replay to the next three full-DL occasions, using the
    % configured TDD symbols and CSI freshness rather than fixed slot IDs.
    for slot=firstSlot:firstSlot+20
        current=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,slot);
        availability=sixgr.phy.frame.SlotFormatResolver.isAvailable( ...
            current.phy.frameStructure.SlotState,slot-1,0, ...
            current.phy.frameStructure.SymbolsPerSlot,'DL');
        if ~availability.Available, continue; end
        assert(slot-retained.feedback.SourceSlot<=sixgr.link.resolveFeedbackMaxAgeSlots(cfg,'DL'));
        state.CurrentSlot=slot;
        carrier=sixgr.phy.grid.makeCarrier(current);
        state.CurrentFrame=carrier.NFrame+1;
        [current,state]=sixgr.truth.CoupledTruthRuntime.applyUserContext(current,state,1,'DL');
        sch=sixgr.l2.mac.SchedulerPF(current,'Direction','DL');
        p=current.phy.pdsch;
        budget=struct('ControlAbsoluteSlot',slot-1,'ControlSymbolAllocation',[0 2]);
        available=sch.ssbSafePRBSet(slot,budget,p.prbSet,p.symbolAllocation);
        [prbs,~]=sixgr.l2.mac.contiguousPRBChunk(available,1,numel(p.prbSet),1);
        grant=struct('Direction','DL','Frame',state.CurrentFrame,'Slot',slot, ...
            'ControlAbsoluteSlot',slot-1,'RNTI',double(p.RNTI),'UEIndex',1,'ServingCell',1, ...
            'PRBSet',prbs,'SymbolAllocation',p.symbolAllocation, ...
            'NumLayers',p.numLayers,'Layers',p.numLayers, ...
            'MCSIndex',p.mcsIndex,'MCS',p.mcsIndex,'Modulation',p.modulation, ...
            'TargetCodeRate',p.codeRate,'CRI',retained.feedback.CRI, ...
            'HARQ',struct('HarqID',height(rows),'NDI',true,'RV',0,'IsRetransmission',false));
        grant=sixgr.truth.CoupledTruthRuntime.applyMeasuredFeedbackAMCToGrantRuntime( ...
            grant,retained.feedback,[],current,'DL');
        grant=sch.attachCanonicalTimingDecision(grant);
        grant=sch.finalizeExactPHYFeasibility(grant);
        assert(grant.Valid && grant.ExactPHYFeasible, ...
            'test:ReplayGrantInfeasible','%s',grant.ExactPHYInfeasibilityReason);
        grant.DCI=sch.buildDCIBitfield(grant);
        frozen=sixgr.phy.grant.freezePHYGrant(current,'DL',grant);
        control=sixgr.link.preparePDCCHTransmission(current,'DCIBits',grant.DCI.Bits,'RNTI',grant.RNTI);
        [decoded,info]=sixgr.phy.dl.PDCCH_Rx(control.TransmitSamples,current, ...
            'SampleRate_Hz',control.SampleRateHz);
        assert(decoded.Ok && isequal(decoded.DCIBits,grant.DCI.Bits));
        assignment=sixgr.phy.pdcch.materializeConnectedDCI(decoded,info,current);
        assert(assignment.NumLayers==retained.feedback.RI && ...
            assignment.MCS==retained.feedback.MCSIndex && assignment.NumPRB==numel(prbs));
        controlRow=table("PASS",logical(decoded.Ok),true,true,false,false, ...
            assignment.TCICodepoint,slot,'VariableNames', ...
            {'Status','DCICrcPass','PDCCHPayloadMatch','PDCCHCausalGrantDecodeOk', ...
             'PDCCHFalseAlarm','PDCCHMissedDetection','DecodedDCITCICodepoint','Slot'});
        [state,grant,allowed]=sixgr.truth.CoupledTruthRuntime.applyPDCCHGrantTrial( ...
            state,grant,'DL',controlRow);
        assert(allowed && state.AppliedDataBeamCRIByUE(1)==retained.feedback.CRI);
        [tx,~]=sixgr.phy.dl.PDSCH_Tx(current,'PHYGrant',frozen, ...
            'SchedulerGrantContext',grant,'CompactOutput',false, ...
            'CellCommonSignalOwnershipMode','reserve_only');
        request=current.phy.csi.reportConfiguration; request.Rank=retained.feedback.RI;
        expected=current.phy.csirs.precoderMatrices(:,:,retained.feedback.CRI+1)* ...
            sixgr.phy.mimo.TypeISinglePanelCodebook.matrix(request,retained.feedback.PMI);
        assert(norm(frozen.PrecodingState.MatrixPorts-expected,'fro')<1e-12 && ...
            size(tx.PDSCHLayerSymbols,2)==assignment.NumLayers && size(tx.Waveform,2)==64 && ...
            isequal(tx.PDSCH.DMRS.DMRSPortSet,assignment.DMRSPortSet));
        if isempty(frozenBefore)
            frozenBefore=frozen;
            frozenOriginal=frozenBefore;
        end
        assert(isequaln(frozenBefore,frozenOriginal));
        row=table(slot,retained.feedback.SourceSlot,retained.feedback.DeliveredSlot, ...
            reports.CQI(end),retained.feedback.CQI,grant.MCSIndex,grant.NumLayers, ...
            grant.PMI,grant.CRI,assignment.TCICodepoint,numel(prbs),numel(tx.TransportBlock), ...
            logical(decoded.Ok),true,false,'VariableNames', ...
            {'Slot','CSIReferenceSlot','CSIDeliverySlot','DecodedCQI','SchedulerCQI', ...
             'MCS','Rank','PMI','CRI','TCICodepoint','NumPRB','TBSBits', ...
             'LogicalLinkPDCCHDecoded','PDSCHTransmitted','ScenarioAccepted'});
        rows=[rows;row]; %#ok<AGROW>
        sixgr.util.csvWriteTable(fullfile(folder,'replay_grants.csv'),rows,'PreserveSchema',true);
        save(fullfile(folder,sprintf('slot%d_grant.mat',slot)), ...
            'grant','frozen','assignment','controlRow');
        fprintf('H4_RETAINED_CSI_GRANT slot=%d rank=%d PMI=%d CRI=%d MCS=%d PRBs=%d\n', ...
            slot,grant.NumLayers,grant.PMI,grant.CRI,grant.MCSIndex,numel(prbs));
        clear tx control
        if height(rows)==3, break; end
    end
    assert(height(rows)==3,'test:ReplayIncomplete','Three legal DL occasions were not verified.');
    receipt.Completed=true; receipt.Ok=true; receipt.GrantCount=height(rows);
catch cause
    receipt.Completed=true; receipt.ErrorID=string(cause.identifier);
    receipt.ErrorReport=string(getReport(cause,'extended','hyperlinks','off'));
    sixgr.util.jsonWrite(fullfile(folder,'receipt.json'),receipt);
    rethrow(cause);
end
sixgr.util.jsonWrite(fullfile(folder,'receipt.json'),receipt);
disp(rows);
fprintf('H4_RETAINED_CSI_GRANT_REPLAY_PASS folder=%s scenario_accepted=0\n',folder);
end
