function ok = testSSSINRPhysicalMeasurement()
%TESTSSSINRPHYSICALMEASUREMENT Verify same-plane SS-SINR without SNR proxy.
rng(7311, "twister");
nCellID = 17;
iBarSSB = 0;
nRx = 2;
signalPower_W = 1e-9;   % -60 dBm per SSS RE before noise
noisePower_W = 1e-10;  % 10 dB SSS SINR
grid = complex(zeros(240, 4, nRx));
grid(nrPSSIndices) = sqrt(signalPower_W) .* nrPSS(nCellID);
grid(nrSSSIndices) = sqrt(signalPower_W) .* nrSSS(nCellID);
grid(nrPBCHIndices(nCellID)) = sqrt(signalPower_W) .* ...
    nrPBCH(randi([0 1], 864, 1), nCellID, 0);
grid(nrPBCHDMRSIndices(nCellID)) = sqrt(signalPower_W) .* ...
    nrPBCHDMRS(nCellID, iBarSSB);
grid(:, :, 2) = grid(:, :, 1);
noise = sqrt(noisePower_W / 2) .* ...
    complex(randn(size(grid)), randn(size(grid)));
rxGrid = grid + noise;

measured = sixgr.phy.refsig.measureSSSINRFromSSBGrid( ...
    rxGrid, nCellID, iBarSSB);
assert(logical(measured.Available) && ...
    all(isfinite(measured.SS_SINRPerReceiveAntenna_dB)), ...
    "Physical SS-SINR measurement must be available on both branches.");
assert(abs(double(measured.SS_SINR_dB) - 10) < 1.5, ...
    "Measured SS-SINR %.3f dB does not close against the 10 dB waveform truth.", ...
    double(measured.SS_SINR_dB));
assert(abs(double(measured.NoiseDebiasedSS_RSRP_dBm) - (-60)) < 1.5 && ...
    double(measured.RawObservedSS_RSRP_dBm) > ...
    double(measured.NoiseDebiasedSS_RSRP_dBm), ...
    ["Noise-debiased SS-RSRP must close to the injected SSS EPRE and " ...
     "remain distinct from the noise-lifted raw observation."]);
assert(double(measured.NoiseInterferenceRECount) > 0 && ...
    contains(string(measured.MeasurementMethod), "same_ssb_bandwidth"), ...
    "SS-SINR must retain its same-bandwidth measured noise/interference evidence.");

% Scaling absolute received power must not alter SINR.
scaled = sixgr.phy.refsig.measureSSSINRFromSSBGrid( ...
    rxGrid .* sqrt(1e-4), nCellID, iBarSSB);
assert(logical(scaled.Available) && ...
    abs(double(scaled.SS_SINR_dB) - double(measured.SS_SINR_dB)) < 1e-9, ...
    "SS-SINR must be invariant to a common waveform power scale.");
assert(abs(double(scaled.NoiseDebiasedSS_RSRP_dBm) - ...
    (double(measured.NoiseDebiasedSS_RSRP_dBm) - 40)) < 1e-9, ...
    "Noise-debiased SS-RSRP must preserve the exact common power scaling.");
ok = true;
end
