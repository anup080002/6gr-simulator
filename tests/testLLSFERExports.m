function ok = testLLSFERExports()
%TESTLLSFEREXPORTS Verify FER is exported from actual raw trial outcomes.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

cfg = sixgr.config.defaultConfig();
runFolder = fullfile(tmp, "run");
mkdir(runFolder);

dlT = table( ...
    [1; 2; 1; 2], [320; 321; 320; 321], [10; 10; 10; 10], [1; 1; 2; 2], [1; 2; 1; 2], [1; 1; 0; 1], [0; 0; 12; 0], [128; 128; 128; 128], ["PASS"; "PASS"; "FAIL"; "PASS"], [0; 0; 0; 0], ...
    'VariableNames', {'UEIndex','RNTI','SNR_dB','Frame','Slot','CRCPass','BitErrors','BitsCompared','Status','Crash'});
ulT = table( ...
    [1; 2; 1; 2], [320; 321; 320; 321], [10; 10; 10; 10], [1; 1; 2; 2], [1; 2; 1; 2], [1; 1; 1; 1], [0; 0; 0; 0], [128; 128; 128; 128], ["PASS"; "PASS"; "PASS"; "PASS"], [0; 0; 0; 0], ...
    'VariableNames', {'UEIndex','RNTI','SNR_dB','Frame','Slot','CRCPass','BitErrors','BitsCompared','Status','Crash'});
rawTrials = struct( ...
    "DL", dlT, ...
    "UL", ulT, ...
    "SRS", table(), ...
    "TRS", table(), ...
    "MultiUserDL", table(), ...
    "MultiUserUL", table());

artifacts = sixgr.truth.exportLLSLiveDerivedTables(cfg, runFolder, rawTrials, struct(), struct(), struct());
summaryT = artifacts.ErrorRateSummary;
userPerfT = artifacts.UserPerformance;
persistedCells = readcell(char(artifacts.ErrorRateSummaryPath), "Delimiter", ",");

assert(istable(summaryT) && ~isempty(summaryT), ...
    "FER export must create a non-empty error-rate summary table.");
assert(exist(char(artifacts.ErrorRateSummaryPath), "file") == 2, ...
    "FER export must persist the live error-rate summary CSV.");

dlRun = summaryT(strcmpi(string(summaryT.Direction), "DL") & strcmpi(string(summaryT.Scope), "run"), :);
ulRun = summaryT(strcmpi(string(summaryT.Direction), "UL") & strcmpi(string(summaryT.Scope), "run"), :);
dlUE = summaryT(strcmpi(string(summaryT.Direction), "DL") & strcmpi(string(summaryT.Scope), "ue"), :);
ulUE = summaryT(strcmpi(string(summaryT.Direction), "UL") & strcmpi(string(summaryT.Scope), "ue"), :);
assert(height(dlRun) == 1 && abs(double(dlRun.FER(1)) - 0.5) < 1e-9, ...
    "DL FER must be 0.5 when one of two observed frames fails.");
assert(height(ulRun) == 1 && abs(double(ulRun.FER(1))) < 1e-9, ...
    "UL FER must be 0 when all observed frames pass.");
assert(~isfinite(double(dlRun.UEID(1))) && ~isfinite(double(dlRun.UEIndex(1))) && ~isfinite(double(dlRun.RNTI(1))), ...
    "Run-scope FER rows must not carry UE identity.");
assert(~isfinite(double(ulRun.UEID(1))) && ~isfinite(double(ulRun.UEIndex(1))) && ~isfinite(double(ulRun.RNTI(1))), ...
    "Run-scope UL FER rows must not carry UE identity.");
assert(strcmpi(char(string(dlRun.ScopeDefinition(1))), "all_ues_in_direction_aggregated_per_frame_no_ue_identity"), ...
    "Run-scope FER rows must disclose that they aggregate all UEs without UE identity.");
assert(height(dlUE) == 2 && height(ulUE) == 2, ...
    "UE-scope FER rows must be emitted separately for each UE.");
assert(all(isfinite(double(dlUE.UEID))) && all(isfinite(double(dlUE.RNTI))), ...
    "UE-scope FER rows may carry UE identity.");
assert(all(strcmpi(string(dlUE.ScopeDefinition), "single_ue_in_direction_aggregated_per_frame")), ...
    "UE-scope FER rows must disclose single-UE aggregation semantics.");
assert(strcmpi(char(string(dlRun.FERDefinition(1))), ...
    "frame_fails_if_any_executed_transport_block_fails_crc_or_crashes"), ...
    "FER rows must disclose the authoritative frame-failure definition.");
assert(strcmpi(char(string(dlRun.TraceSource(1))), "dl_frame_grouped_raw_link_trials"), ...
    "FER rows must disclose the raw runtime source.");
persistedHeader = string(persistedCells(1, :));
dirCol = find(strcmpi(persistedHeader, "Direction"), 1, "first");
scopeCol = find(strcmpi(persistedHeader, "Scope"), 1, "first");
rntiCol = find(strcmpi(persistedHeader, "RNTI"), 1, "first");
assert(~isempty(dirCol) && ~isempty(scopeCol) && ~isempty(rntiCol), ...
    "Persisted FER CSV must retain Direction/Scope/RNTI columns.");
persistedRows = persistedCells(2:end, :);
runMask = strcmpi(string(persistedRows(:, dirCol)), "DL") & strcmpi(string(persistedRows(:, scopeCol)), "run");
assert(nnz(runMask) == 1, "Persisted FER CSV must contain one DL run-scope row.");
persistedRNTI = persistedRows{find(runMask, 1, "first"), rntiCol};
assert(isempty(persistedRNTI) || (isstring(persistedRNTI) && strlength(strtrim(persistedRNTI)) == 0) || (isnumeric(persistedRNTI) && ~isfinite(persistedRNTI)), ...
    "Persisted FER CSV must keep run-scope RNTI blank.");

assert(istable(userPerfT) && height(userPerfT) == 2, ...
    "User performance export must expose one per-UE row for the FER probe.");
ue1 = userPerfT(abs(double(userPerfT.UEIndex) - 1) < 1e-9, :);
ue2 = userPerfT(abs(double(userPerfT.UEIndex) - 2) < 1e-9, :);
assert(height(ue1) == 1 && height(ue2) == 1, ...
    "User performance export must preserve per-UE FER separation.");
assert(abs(double(ue1.DL_FER(1)) - 0.5) < 1e-9 && abs(double(ue1.UL_FER(1))) < 1e-9, ...
    "UE1 user performance export must carry DL/UL FER derived from raw runtime trials.");
assert(abs(double(ue2.DL_FER(1))) < 1e-9 && abs(double(ue2.UL_FER(1))) < 1e-9, ...
    "UE2 user performance export must carry clean per-UE FER without run-scope leakage.");

ok = true;
end
