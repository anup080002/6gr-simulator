function ok = testCoupledTruthCSIReportSourceAuthority()
%TESTCOUPLEDTRUTHCSIREPORTSOURCEAUTHORITY Keep CSI producer labels truthful.
% Declared measurement/ledger inputs and actual UCI codecs, not CSI-RS RF evidence.

setup6GRSimToolkit("Verbose", false);
tmp = tempname;
mkdir(tmp);
cleanup = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

scenario = sixgr.lls6g.config.loadScenarioConfig(fullfile( ...
    "simulator", "configs", "scenarios", ...
    "lls_csi_source_authority_fixture.yaml"));
cfg = sixgr.lls6g.buildInternalConfig(scenario, fullfile(tmp, "run"));
assert(cfg.phy.csi.reportConfiguration.NumCSIResources==4 && ...
    cfg.phy.csi.reportConfiguration.NumberOfBeams==4 && ...
    cfg.phy.csirs.numResources==4 && isequal(double(cfg.phy.csirs.resourceIDs(:).'),0:3));
inconsistent=scenario.toStruct();
inconsistent.mimo.phase07_strict.csi_report.number_of_beams=1;
localRejectCRI(@()sixgr.lls6g.buildInternalConfig(inconsistent,fullfile(tmp,'invalid_beams')), ...
    'sixgr:mimo:CSIReportResourceMismatch');
for cri=0:3, assert(sixgr.truth.validateMeasuredCRI(cri,4)==cri); end
assert(isnan(sixgr.truth.validateMeasuredCRI(NaN,4)) && ...
    isnan(sixgr.truth.validateMeasuredCRI([],4)));
for invalid={-1,4,Inf,0.25,1i,[0 1],'0'}
    localRejectCRI(@()sixgr.truth.validateMeasuredCRI(invalid{1},4));
end
for invalidCount={0,1.5,NaN,Inf,[1 2]}
    localRejectCRI(@()sixgr.truth.validateMeasuredCRI(0,invalidCount{1}), ...
        'sixgr:mimo:InvalidCSIResourceCount');
end
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.phy.csirs.enable = true;
multiUser = struct("Enabled", true, "NumUsers", 1, "RNTIStart", 701, ...
    "ExecutionModel", "slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfg, fullfile(tmp, "runtime"), multiUser, struct(), 2);
state.CurrentServingIdx(:)=1; % Explicit CSI/HARQ component-fixture serving cell.

state.CurrentSlot = 4;
dmrsRow = table(4, 10, 8.5, 1, 0, true, true, 2, 17, ...
    "receiver_post_equalization_sinr", ...
    "measured_post_equalization_scheduling_input", "OK", ...
    'VariableNames', {'Slot','WidebandCQI','SINR_dB','RIEstimate', ...
    'PMI','CRCPass','MUMIMOEnabled','MUMIMOGroupSize','MUMIMOGroupId', ...
    'SINRSource','SINRValueRole','SINRValueStatus'});
dmrsRow.CRI=0; % Explicit component report selection; never inferred by runtime.
missingCRI=dmrsRow; missingCRI.CRI=NaN;
localRejectCRI(@()sixgr.truth.CoupledTruthRuntime.enqueueCSIReportRuntime( ...
    state,1,"DL",missingCRI,cfg,table()));
state = sixgr.truth.CoupledTruthRuntime.enqueueCSIReportRuntime( ...
    state, 1, "DL", dmrsRow, cfg, table());
assert(string(state.PendingCSITable.SourceSignal(end)) == "PDSCH-DMRS", ...
    "A DL report without an observed CSI-RS producer must remain PDSCH-DMRS sourced.");
assert(logical(state.PendingCSITable.MUMIMOEnabled(end)) && ...
    double(state.PendingCSITable.MUMIMOGroupSize(end)) == 2 && ...
    double(state.PendingCSITable.MUMIMOGroupId(end)) == 17, ...
    ["Delayed feedback must retain the measured source grant's shared-MU " ...
     "identity so first-data bootstrap authority can release causally."]);

state.CurrentSlot = 5;
ulRow = dmrsRow;
ulRow.Slot(:) = 5;
state = sixgr.truth.CoupledTruthRuntime.enqueueCSIReportRuntime( ...
    state, 1, "UL", ulRow, cfg, table());
assert(string(state.PendingCSITable.SourceSignal(end)) == "PUSCH-DMRS", ...
    "An UL report without an observed SRS producer must remain PUSCH-DMRS sourced.");

state.CurrentSlot = 6;
csirsRow = table(true, true, true, 12, 2, 1, 3, 11.25, ...
    "received_csirs_post_equalization_sinr", ...
    "measured_reference_signal_scheduling_input", "OK", ...
    "nrCSIRSMeasurements_runtime_received_grid", ...
    'VariableNames', {'Observed','CSIMeasurementAvailable', ...
    'ChannelEstimateAvailable','CQI','RI','PMI','CRI','SINR_dB', ...
    'SINRSource','SINRValueRole','SINRValueStatus','MeasurementSource'});
csirsTrial = dmrsRow;
csirsRow.LI=0; % Explicit receiver-measurement fixture: first layer strongest.
csirsRow.Slot=6;
csirsRow.Transmitted=true;
csirsRow.Consumed=true;
csirsRow.ResourceExtractionAvailable=true;
csirsTrial.Slot(:) = 6;
state = sixgr.truth.CoupledTruthRuntime.applyCSIRSTrial(state,1,csirsRow);
state = sixgr.truth.CoupledTruthRuntime.enqueueCSIReportRuntime( ...
    state, 1, "DL", csirsTrial, cfg, csirsRow);
assert(string(state.PendingCSITable.SourceSignal(end)) == "CSI-RS" && ...
    double(state.PendingCSITable.CQI(end)) == 12 && ...
    double(state.PendingCSITable.RI(end)) == 2 && ...
    double(state.PendingCSITable.PMI(end)) == 1 && ...
    double(state.PendingCSITable.CRI(end)) == 3, ...
    "Observed CSI-RS reports must preserve the receiver-owned CQI/RI/PMI/CRI values.");

% UL-direction CSI is gNB-side channel knowledge derived from SRS. It is
% not UE-originated UCI and must never suppress a same-UE PUSCH through the
% PUCCH collision resolver. This reproduces the real multi-user run defect
% where not_scheduled UL CSI rows removed valid future PUSCH grants.
uplinkCSIState = state;
uplinkCSIState.PendingCSITable = uplinkCSIState.PendingCSITable(end, :);
uplinkCSIState.PendingCSITable.Direction(:) = "UL";
uplinkCSIState.PendingCSITable.Processed(:) = false;
uplinkCSIState.PendingCSITable.RightCensored(:) = false;
uplinkCSIState.PendingCSITable.CSIUCITransport(:) = "pucch";
uplinkCSIState.PendingCSITable.CSIUCIMultiplexedOnPUSCH(:) = false;
uplinkCSIState.PendingCSITable.CSIUCIPUSCHGrantContextId(:) = "";
ulKnowledgeDueSlot = double(uplinkCSIState.PendingCSITable.DueSlot(1));
ulKnowledgeGrant = struct("Direction", "UL", "UEIndex", 1, ...
    "RNTI", 701, "GrantContextId", "UL-SRS-KNOWLEDGE-PUSCH", ...
    "Slot", ulKnowledgeDueSlot, ...
    "ScheduledAbsoluteSlot", ulKnowledgeDueSlot);
[retainedULKnowledgeGrant, falseCollisionRows] = ...
    sixgr.truth.CoupledTruthRuntime. ...
    excludeULGrantsCollidingWithPUCCHRuntime( ...
    uplinkCSIState, ulKnowledgeGrant, ulKnowledgeDueSlot);
assert(numel(retainedULKnowledgeGrant) == 1 && isempty(falseCollisionRows), ...
    "UL/SRS-derived CSI knowledge must not be treated as a UE PUCCH " + ...
    "occasion or suppress a same-slot PUSCH.");

% A qualified same-UE PUSCH in the feedback slot must carry the typed CSI
% payload rather than collide with a standalone Format-2 PUCCH.  Only the
% receiver-decoded bit vectors may enter the scheduler state.
state.PendingCSITable = state.PendingCSITable(end, :);
dueSlot = double(state.PendingCSITable.DueSlot(1));
reportIdentity = string(state.PendingCSITable.ReportIdentity(1));
% Explicit scheduler-ledger fixture; no standalone PUCCH waveform is claimed.
reservation=localFeedbackRow();
reservation.Direction="DL"; reservation.UEIndex=1; reservation.RNTI=701;
reservation.SourceSlot=double(state.PendingCSITable.SourceSlot(1)); reservation.DueSlot=dueSlot;
reservation.ServingCell=1; reservation.BaseStationID=1;
reservation.ComponentCarrier=cfg.phy.frame.DefaultIdentity.ScheduledCCID;
reservation.ActiveULBWP=cfg.phy.frame.DefaultIdentity.ULBWPID;
reservation.PUCCHGrantId="PUCCH-CSI-"+reportIdentity;
reservation.UCIType="csi_part1_part2";
reservation.UCIBitCount=double(state.PendingCSITable.CSIUCIBitCount(1));
reservation.ControlResourceSource="explicit_CSI_transport_ledger_component_fixture";
% Preserve the original malformed reservation as a negative test. CSI-only
% reservations must carry configured CSI authority, never a HARQ DCI PRI.
localRejectCRI(@()sixgr.truth.CoupledTruthRuntime.schedulePUCCHGrantRuntime( ...
    state,struct2table(reservation)),'sixgr:truth:InvalidCSIResourceProvenance');
authority=sixgr.phy.pucch.resolveConfiguredPRI(cfg,reservation.UEIndex, ...
    reservation.RNTI,NaN,'csi');
ue=struct('UEID',reservation.UEIndex,'RNTI',reservation.RNTI, ...
    'ServingCell',reservation.ServingCell,'PUCCHCell',reservation.ServingCell, ...
    'ComponentCarrier',reservation.ComponentCarrier,'ActiveULBWP',reservation.ActiveULBWP);
rrc=sixgr.phy.pucch.PUCCHConfigBuilder.receiverConfiguration(cfg,ue);
resource=rrc.resourceByID(authority.ResourceId);
reservation.PRIValue=authority.PRIValue;
reservation.PRIProvenance=authority.Source;
reservation.PUCCHResourceId=string(resource.ID);
reservation.RequestedFormat=resource.Format;
reservation.ResolvedFormat=resource.Format;
reservation.PUCCHPRBStart=resource.Data.StartPRB;
reservation.PUCCHPRBCount=resource.Data.NumPRBs;
reservation.PUCCHSymbolStart=resource.Data.StartSymbol;
reservation.PUCCHNumSymbols=resource.Data.NumSymbols;
reservation.ControlResourceValidity=true; % Exact configured resource above, not RF success.
badPRI=reservation; badPRI.PRIValue=0;
localRejectCRI(@()sixgr.truth.CoupledTruthRuntime.schedulePUCCHGrantRuntime( ...
    state,struct2table(badPRI)),'sixgr:truth:InvalidCSIResourceProvenance');
state=sixgr.truth.CoupledTruthRuntime.schedulePUCCHGrantRuntime(state,struct2table(reservation));
csiReservation=state.PUCCHGrantTraceTable( ...
    string(state.PUCCHGrantTraceTable.PUCCHGrantId)==reservation.PUCCHGrantId,:);
assert(height(csiReservation)==1 && isnan(csiReservation.PRIValue) && ...
    string(csiReservation.PRIProvenance)==string(authority.Source) && ...
    string(csiReservation.PUCCHResourceId)==string(resource.ID) && ...
    isnan(csiReservation.TBSBits) && ~csiReservation.GrantExecutedFlag, ...
    'Configured CSI reservation must not manufacture HARQ PRI, TBS or PUCCH execution.');
puschGrant = struct("Direction", "UL", "UEIndex", 1, "RNTI", 701, ...
    "GrantContextId", "CSI-PUSCH-CONTEXT", "Slot", dueSlot, ...
    "ScheduledAbsoluteSlot", dueSlot,"SymbolAllocation",[resource.Data.StartSymbol resource.Data.NumSymbols]);
for enabled=[false true]
    disjoint=puschGrant; disjoint.SymbolAllocation=[0 10];
    [untouched,retained,blocked]=sixgr.truth.CoupledTruthRuntime. ...
        reconcileQueuedPUSCHAfterDLFeedbackRuntime(state,disjoint,enabled);
    assert(isempty(blocked) && numel(retained)==1 && ...
        ~logical(sixgr.util.structGet(retained,'UCIOnPUSCHApplied',false)) && ...
        isequaln(untouched.PendingCSITable,state.PendingCSITable), ...
        'Nonoverlapping CSI PUCCH must retain its typed report and standalone transport.');
end
% Equal RNTI is not permission to transfer a different runtime UE's CSI.
otherUEGrant=puschGrant; otherUEGrant.UEIndex=2; otherUEGrant.ServingCell=2;
[otherState,otherGrant,otherBlocked]=sixgr.truth.CoupledTruthRuntime. ...
    reconcileQueuedPUSCHAfterDLFeedbackRuntime(state,otherUEGrant,true);
assert(isempty(otherBlocked) && numel(otherGrant)==1 && ...
    ~logical(sixgr.util.structGet(otherGrant,'UCIOnPUSCHApplied',false)) && ...
    isequaln(otherState.PendingCSITable,state.PendingCSITable) && ...
    ~any(otherState.PUCCHGrantTraceTable.MultiplexedOnPUSCH), ...
    'A different runtime UE must neither consume CSI nor suppress its own PUSCH through RNTI equality.');
% A CSI reservation becoming visible between post-DL reconciliation and
% UL slot entry must still bind before the PUCCH receiver can consume it.
[entryState,entryGrant,entryBlocked]=sixgr.truth.CoupledTruthRuntime.startSlotWithQueuedUL( ...
    state,cfg,'UL',1,1,dueSlot,max(10,dueSlot),12,puschGrant,true);
assert(isempty(entryBlocked) && ~entryState.PendingCSITable.Processed(1) && ...
    string(entryState.PendingCSITable.CSIUCITransport(1))=="pusch_bound" && ...
    ~isempty(entryGrant.ExpectedUCIPayload.CSIPart1) && ...
    isempty(entryState.PUCCHExecutedCurrentSlotGrantSnapshot), ...
    'Due-slot CSI must be reserved on queued PUSCH before standalone PUCCH execution.');
[state, puschGrant] = sixgr.truth.CoupledTruthRuntime. ...
    multiplexDueHARQACKOnPUSCHRuntime(state, puschGrant, dueSlot);
assert(isa(puschGrant.ExpectedUCIPayload, ...
    "sixgr.phy.ul.pusch.PUSCHUCIPayload") && ...
    isempty(puschGrant.ExpectedUCIPayload.HARQACK) && ...
    ~isempty(puschGrant.ExpectedUCIPayload.CSIPart1) && ...
    logical(state.PendingCSITable.CSIUCIMultiplexedOnPUSCH(1)) && ...
    string(state.PendingCSITable.CSIUCITransport(1)) == "pusch_bound", ...
    "Due CSI must bind to the exact queued PUSCH typed-UCI payload.");
boundTrace=state.PUCCHGrantTraceTable(string(state.PUCCHGrantTraceTable.PUCCHGrantId)== ...
    "PUCCH-CSI-"+reportIdentity,:);
boundCSI=puschGrant.ExpectedUCIPayload;
assert(height(boundTrace)==1 && boundTrace.UCIBitCount== ...
    numel(boundCSI.CSIPart1)+numel(boundCSI.CSIPart2) && ...
    string(state.PendingCSITable.CSIUCIChannel(1))=="PUSCH", ...
    'The transferred CSI ledger must count actual PUSCH bits, not retain PUCCH padding.');

localCheckReceivedPUSCHLengthAuthority(state,puschGrant,dueSlot);

% Reproduce the production queue/cache boundary: the pending CSI row keeps
% its exact PUSCH reservation, while a rebuilt live grant contains no
% occasion-local UCI fields.  The due-slot resolver must recover the typed
% payload from the pending measured report instead of orphaning it as a
% terminal right-censored row.
rebuiltGrant = puschGrant;
rebuiltGrant.ExpectedUCIPayload = [];
rebuiltGrant.ExpectedUCIBits = int8([]);
rebuiltGrant.MultiplexedHARQACKBits = int8([]);
rebuiltGrant.UCIOnPUSCHApplied = false;
rebuiltGrant.UCIOnPUSCHCSIReportIdentity = "";
rebuiltGrant.UCIOnPUSCHCSIPart1BitCount = 0;
rebuiltGrant.UCIOnPUSCHCSIPart2BitCount = 0;
[state, recoveredGrant] = sixgr.truth.CoupledTruthRuntime. ...
    multiplexDueHARQACKOnPUSCHRuntime(state, rebuiltGrant, dueSlot);
assert(isa(recoveredGrant.ExpectedUCIPayload, ...
    "sixgr.phy.ul.pusch.PUSCHUCIPayload") && ...
    string(recoveredGrant.UCIOnPUSCHCSIReportIdentity) == reportIdentity && ...
    isequal(int8(recoveredGrant.ExpectedUCIPayload.CSIPart1(:)), ...
        int8(puschGrant.ExpectedUCIPayload.CSIPart1(:))), ...
    "A rebuilt live PUSCH grant must recover its exact due CSI payload.");

% Reproduce the complete causal boundary that previously orphaned both
% control payloads: CSI is already reserved on the queued future PUSCH,
% then a PDSCH decode creates a HARQ-ACK for that same UE and due slot.  A
% later cache rebuild changes the frozen grant context.  Sanitizing the
% stale binding must atomically release *both* pending lineages and rebind
% them to the current context; retaining only CSI silently loses HARQ and
% retaining only HARQ silently loses CSI.
combinedState = state;
feedback = localFeedbackRow();
feedback.Direction = "DL";
feedback.UEIndex = 1;
feedback.RNTI = 701;
feedback.HarqID = 3;
feedback.NDI = 1;
feedback.RV = 0;
feedback.SourceSlot = dueSlot - 1;
feedback.DueSlot = dueSlot;
feedback.Ack = true;
feedback.CurrentDecodeOK = true;
feedback.CombinedDecodeOK = true;
feedback.ServingCell = 1;
feedback.BaseStationID = 1;
feedback.ComponentCarrier = cfg.phy.frame.DefaultIdentity.ScheduledCCID;
feedback.ActiveULBWP = cfg.phy.frame.DefaultIdentity.ULBWPID;
feedback.TBSBits = 64;
feedback.UCIBitCount = 1;
feedback.RequestedFormat = 1;
feedback.ResolvedFormat = 1;
feedback.PUCCHResourceId = "PUCCH-COMBINED-UCI";
feedback.PUCCHPRBStart = 0;
feedback.PUCCHPRBCount = 1;
feedback.PUCCHSymbolStart = 12;
feedback.PUCCHNumSymbols = 2;
feedback.UCIType = "harq_ack";
feedback.ControlResourceSource = "focused_runtime_fixture";
feedback.ControlResourceValidity = true;
feedback.FormatAdaptationReason = "none_strict_assignment";
feedback.PUCCHGrantId = "PUCCH-COMBINED-UCI-GRANT";
combinedState.PendingFeedbackTable = struct2table(feedback, "AsArray", true);
combinedState = sixgr.truth.CoupledTruthRuntime.schedulePUCCHGrantRuntime( ...
    combinedState, combinedState.PendingFeedbackTable(1, :));
[combinedState, combinedGrant, blocked] = sixgr.truth.CoupledTruthRuntime. ...
    reconcileQueuedPUSCHAfterDLFeedbackRuntime( ...
    combinedState, recoveredGrant, true);
assert(isempty(blocked) && numel(combinedGrant) == 1 && ...
    isa(combinedGrant.ExpectedUCIPayload, ...
        "sixgr.phy.ul.pusch.PUSCHUCIPayload") && ...
    isequal(int8(combinedGrant.ExpectedUCIPayload.HARQACK(:)), int8(1)) && ...
    ~isempty(combinedGrant.ExpectedUCIPayload.CSIPart1) && ...
    string(combinedState.PendingFeedbackTable.DeliveryMechanism(1)) == ...
        "pusch_uci" && ...
    logical(combinedState.PendingCSITable.CSIUCIMultiplexedOnPUSCH(1)), ...
    "Late HARQ-ACK must merge with already-bound CSI on the same exact PUSCH.");

% Reproduce the due-slot cache defect observed in the real waveform run:
% both ledgers are already bound to the exact current grant context, but the
% reconstructed live grant exposes only its earlier CSI reservation.  The
% complete authoritative ledger must rebuild the omitted HARQ lineage even
% though the context identity itself did not change.
partialExactGrant = combinedGrant;
partialExactGrant.ExpectedUCIPayload = sixgr.phy.ul.pusch.PUSCHUCIPayload( ...
    "HARQACK", int8([]), ...
    "CSIPart1", combinedGrant.ExpectedUCIPayload.CSIPart1, ...
    "CSIPart2", combinedGrant.ExpectedUCIPayload.CSIPart2, ...
    "CSIPart2DependsOnPart1", ...
    ~isempty(combinedGrant.ExpectedUCIPayload.CSIPart2));
partialExactGrant.ExpectedUCIBits = int8([]);
partialExactGrant.MultiplexedHARQACKBits = int8([]);
partialExactGrant.UCIOnPUSCHFeedbackGrantIds = "";
partialExactGrant.UCIOnPUSCHFeedbackSourceSlots = [];
partialExactGrant.UCIOnPUSCHFeedbackHARQIds = [];
partialExactGrant.UCIOnPUSCHFeedbackBitCount = 0;
[exactLedgerState, exactLedgerGrant] = ...
    sixgr.truth.CoupledTruthRuntime.multiplexDueHARQACKOnPUSCHRuntime( ...
    combinedState, partialExactGrant, dueSlot);
assert(isequal(int8(exactLedgerGrant.ExpectedUCIPayload.HARQACK(:)), ...
        int8(1)) && ...
    ~isempty(exactLedgerGrant.ExpectedUCIPayload.CSIPart1) && ...
    string(exactLedgerGrant.UCIOnPUSCHFeedbackGrantIds) == ...
        "PUCCH-COMBINED-UCI-GRANT" && ...
    string(exactLedgerState.PendingFeedbackTable.PUSCHGrantContextId(1)) == ...
        string(combinedGrant.GrantContextId), ...
    "An exact-context CSI-only live grant must be rebuilt from the complete " + ...
    "bound HARQ/CSI ledgers before PUSCH waveform execution.");

staleCombinedGrant = combinedGrant;
staleCombinedGrant.GrantContextId = "CSI-HARQ-PUSCH-CONTEXT-REBUILT";
[reboundState, reboundCombinedGrant] = sixgr.truth.CoupledTruthRuntime. ...
    multiplexDueHARQACKOnPUSCHRuntime( ...
    combinedState, staleCombinedGrant, dueSlot);
assert(isequal(int8(reboundCombinedGrant.ExpectedUCIPayload.HARQACK(:)), ...
        int8(1)) && ...
    ~isempty(reboundCombinedGrant.ExpectedUCIPayload.CSIPart1) && ...
    string(reboundState.PendingFeedbackTable.PUSCHGrantContextId(1)) == ...
        "CSI-HARQ-PUSCH-CONTEXT-REBUILT" && ...
    string(reboundState.PendingCSITable.CSIUCIPUSCHGrantContextId(1)) == ...
        "CSI-HARQ-PUSCH-CONTEXT-REBUILT", ...
    "A rebuilt frozen PUSCH context must atomically release and rebind " + ...
    "both HARQ and CSI rather than orphaning either control payload.");
puschGrant = recoveredGrant;
state.CurrentSlot = dueSlot;
state.CurrentCanonicalSlot = dueSlot;
harqOut = struct("GrantSnapshot", puschGrant, ...
    "ExpectedCSIPart1Bits", puschGrant.ExpectedUCIPayload.CSIPart1, ...
    "ExpectedCSIPart2Bits", puschGrant.ExpectedUCIPayload.CSIPart2, ...
    "ExpectedHARQACKBits", int8([]), "DecodedHARQACKBits", int8([]));
% Actual multiplexing, received Part-1 sizing and NR UCI decoder outputs;
% this is a codec/ledger component, not a channel trial.
payload=puschGrant.ExpectedUCIPayload;
p=nrPUSCHConfig; p.PRBSet=0:11;
config=sixgr.phy.mimo.CSIReportConfiguration(state.CfgMobility.phy.csi.reportConfiguration, ...
    double(state.PendingCSITable.CSIConfigurationEpoch(1)));
config=config.forTransport("PUSCH");
info=nrULSCHInfo(p,.3,512,0,numel(payload.CSIPart1),numel(payload.CSIPart2));
mux=sixgr.phy.ul.pusch.PUSCHUCIMultiplexer.multiplex( ...
    p,.3,512,zeros(info.GULSCH,1,'int8'),payload,4);
received=sixgr.phy.ul.pusch.PUSCHUCIDemultiplexer.demultiplex( ...
    p,.3,512,localPUSCHLLR(p,mux.Codewords{1}),payload,4,config);
harqOut.DecodedCSIPart1Bits=received.DecodedCSIPart1;
harqOut.DecodedCSIPart2Bits=received.DecodedCSIPart2;
harqOut.UCIReceiverEvidence=received.UCIReceiverEvidence;
state.PendingCSITable.LI(1)=1; % Stale local value must not override decoded bits.
state = sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHUCIRuntime( ...
    state, harqOut);
assert(isnan(state.PendingCSITable.LI(1)), ...
    'cri-RI-PMI-CQI does not report LI; a stale local LI must not become received feedback.');
assert(logical(state.PendingCSITable.Processed(1)) && ...
    string(state.PendingCSITable.CSIUCITransport(1)) == "pusch_decoded" && ...
    logical(state.PendingCSITable.CSIUCIDecodeOk(1)) && ...
    double(state.PendingCSITable.CQI(1)) == 12 && ...
    logical(state.LatestDLFeedback(1).Valid) && ...
    double(state.LatestDLFeedback(1).SchedulerCQIRawCQI) == 12 && ...
    double(state.LatestDLFeedback(1).CQI) <= 12, ...
    "Scheduler CSI must come from the PUSCH receiver-decoded payload, " + ...
    "not the transmitter-side report struct; any subsequent temporal " + ...
    "smoothing must remain separately traceable.");
csiTrace=state.PUCCHGrantTraceTable(string(state.PUCCHGrantTraceTable.PUCCHGrantId)=="PUCCH-CSI-"+reportIdentity,:);
assert(height(csiTrace)==1 && csiTrace.MultiplexedOnPUSCH && ...
    ~csiTrace.GrantExecutedFlag && ~csiTrace.PUCCHDecodeOk && ...
    csiTrace.PUSCHUCIDecodeOk && csiTrace.RuntimeStateUpdated && ...
    csiTrace.UCIBitCount==state.PendingCSITable.CSIUCIBitCount(1) && ...
    string(csiTrace.PUCCHGrantState)=="pusch_csi_feedback_applied", ...
    'PUSCH CSI must close its transferred ledger without inventing a standalone PUCCH execution.');

% Reusing a PUSCH/HARQ snapshot on a later CSI occasion must not replay the
% old typed payload.  The occasion sanitizer must discard the stale report
% identity and bind the newly due report to the new frozen grant context.
state.CurrentSlot = dueSlot + 1;
csirsTrial.Slot(:) = state.CurrentSlot;
csirsRow.CQI(:) = 8;
csirsRow.Slot(:) = state.CurrentSlot;
state = sixgr.truth.CoupledTruthRuntime.applyCSIRSTrial(state,1,csirsRow);
state = sixgr.truth.CoupledTruthRuntime.enqueueCSIReportRuntime( ...
    state, 1, "DL", csirsTrial, cfg, csirsRow);
state.PendingCSITable = state.PendingCSITable(end, :);
newDueSlot = double(state.PendingCSITable.DueSlot(1));
newReportIdentity = string(state.PendingCSITable.ReportIdentity(1));
staleReusedGrant = puschGrant;
staleReusedGrant.Slot = newDueSlot;
staleReusedGrant.ScheduledAbsoluteSlot = newDueSlot;
staleReusedGrant.GrantContextId = "CSI-PUSCH-CONTEXT-REUSED";
[state, reboundGrant] = sixgr.truth.CoupledTruthRuntime. ...
    multiplexDueHARQACKOnPUSCHRuntime(state, staleReusedGrant, newDueSlot);
assert(string(reboundGrant.UCIOnPUSCHCSIReportIdentity) == ...
    newReportIdentity && ...
    string(state.PendingCSITable.CSIUCIPUSCHGrantContextId(1)) == ...
    "CSI-PUSCH-CONTEXT-REUSED" && ...
    isequal(int8(reboundGrant.ExpectedUCIPayload.CSIPart1(:)), ...
    int8(sixgr.runtime.RawCSVArrayCodec.decode( ...
    string(state.PendingCSITable.CSIPart1BitsToken(1))))), ...
    "A reused PUSCH grant must discard stale typed CSI and bind only the " + ...
    "currently due receiver report and frozen grant context.");

refT = state.ReferenceSignalMeasurementTable;
assert(any(string(refT.SignalType) == "PDSCH-DMRS") && ...
    any(string(refT.SignalType) == "PUSCH-DMRS") && ...
    any(string(refT.SignalType) == "CSI-RS"), ...
    "Reference-signal evidence must preserve the actual producer signal for each report.");

ok = true;
end

function localRejectCRI(action,identifier)
if nargin<2, identifier='sixgr:mimo:InvalidCRI'; end
try
    action();
catch cause
    assert(strcmp(cause.identifier,identifier), ...
        'Expected %s, got %s: %s',identifier,cause.identifier,cause.message);
    return;
end
error('test:MissingCRIRejection','A malformed CSI resource measurement must not be serialized.');
end

function localCheckReceivedPUSCHLengthAuthority(state,grant,dueSlot)
% Actual UCI codecs and a scheduler-ledger fixture, not an RF/access claim.
payload=grant.ExpectedUCIPayload;
assert(~isempty(payload.CSIPart2));
request=state.CfgMobility.phy.csi.reportConfiguration;
config=sixgr.phy.mimo.CSIReportConfiguration(request, ...
    double(state.PendingCSITable.CSIConfigurationEpoch(1)));
config=config.forTransport("PUSCH");
p=nrPUSCHConfig; p.PRBSet=0:11;
info=nrULSCHInfo(p,.3,512,0,numel(payload.CSIPart1),numel(payload.CSIPart2));
mux=sixgr.phy.ul.pusch.PUSCHUCIMultiplexer.multiplex( ...
    p,.3,512,zeros(info.GULSCH,1,'int8'),payload,4);
poison=sixgr.phy.ul.pusch.PUSCHUCIPayload('CSIPart1',payload.CSIPart1, ...
    'CSIPart2',[payload.CSIPart2;int8(0)]);
received=sixgr.phy.ul.pusch.PUSCHUCIDemultiplexer.demultiplex( ...
    p,.3,512,localPUSCHLLR(p,mux.Codewords{1}),poison,4,config);
assert(isequal(received.DecodedCSIPart2,payload.CSIPart2) && ~received.CSI2ContentMatch);
% Poison only stored TX-reference metadata, not the encoded samples or
% received evidence. Keep the diagnostic binding check internally consistent.
state.PendingCSITable.CSIPart2BitsToken(1)=string(sixgr.runtime.RawCSVArrayCodec.encode(poison.CSIPart2));
state.CurrentSlot=dueSlot;
out=struct('GrantSnapshot',grant,'ExpectedHARQACKBits',int8([]), ...
    'ExpectedCSIPart1Bits',poison.CSIPart1,'ExpectedCSIPart2Bits',poison.CSIPart2, ...
    'DecodedCSIPart1Bits',received.DecodedCSIPart1,'DecodedCSIPart2Bits',received.DecodedCSIPart2, ...
    'UCIReceiverEvidence',received.UCIReceiverEvidence);
missing=out; missing.UCIReceiverEvidence=rmfield(missing.UCIReceiverEvidence,'CSI2LengthAuthority');
rejected=false;
try
    sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHUCIRuntime(state,missing);
catch err
    assert(strcmp(err.identifier,'sixgr:truth:MissingReceivedCSILengthAuthority')); rejected=true;
end
assert(rejected,'Runtime must reject CSI with no received sizing authority.');
% Declared reducer inputs for absent/unresolved receiver decisions. These
% are not RF evidence; actual presence waveforms have their own regression.
for presenceResolved=[true false]
    unavailable=out;
    unavailable.DecodedCSIPart1Bits=int8([]);
    unavailable.DecodedCSIPart2Bits=int8([]);
    unavailable.UCIReceiverEvidence.CSIPresenceResolved=presenceResolved;
    unavailable.UCIReceiverEvidence.CSIReportDetected=false;
    unavailable.UCIReceiverEvidence.CSIPart1DecodedBeforePart2=false;
    unavailable.UCIReceiverEvidence.ResolvedCSI1BitCount=NaN;
    unavailable.UCIReceiverEvidence.ResolvedCSI2BitCount=NaN;
    unavailable.UCIReceiverEvidence.CSI2LengthAuthority="unresolved_csi_presence_or_received_part1";
    if presenceResolved
        unavailable.UCIReceiverEvidence.ResolvedCSI1BitCount=0;
        unavailable.UCIReceiverEvidence.ResolvedCSI2BitCount=0;
        unavailable.UCIReceiverEvidence.CSI2LengthAuthority="explicit_fixed_length_uci_contract";
    end
    rejectedState=sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHUCIRuntime(state,unavailable);
    assert(rejectedState.PendingCSITable.Processed(1) && ...
        ~rejectedState.PendingCSITable.CSIUCIDecodeOk(1) && ...
        isnan(rejectedState.PendingCSITable.CSIUCICRCPass(1)) && ...
        rejectedState.PendingCSITable.CSIUCIDecodedBitCount(1)==0 && ...
        string(rejectedState.PendingCSITable.CSIUCITransport(1))=="pusch_decode_failed");
    assert(isequaln(rejectedState.LatestDLFeedback,state.LatestDLFeedback), ...
        'Unavailable CSI must not replace the last scheduler feedback.');
    rejectedTrace=rejectedState.PUCCHGrantTraceTable;
    rejectedHit=string(rejectedTrace.PUCCHGrantId)=="PUCCH-CSI-"+string(state.PendingCSITable.ReportIdentity(1));
    assert(nnz(rejectedHit)==1 && ~rejectedTrace.PUSCHUCIDecodeOk(rejectedHit) && ...
        ~rejectedTrace.ControlStateChanged(rejectedHit) && ~rejectedTrace.GrantExecutedFlag(rejectedHit));
    malformed=unavailable;
    malformed.UCIReceiverEvidence=rmfield(malformed.UCIReceiverEvidence,'CSI2LengthAuthority');
    localRejectCRI(@()sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHUCIRuntime(state,malformed), ...
        'sixgr:truth:MissingReceivedCSILengthAuthority');
end
malformed=out; malformed.UCIReceiverEvidence.CSI2LengthAuthority="stored_tx_payload";
localRejectCRI(@()sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHUCIRuntime(state,malformed), ...
    'sixgr:truth:MissingReceivedCSILengthAuthority');
% Same received CSI bits; only UE-side fields NOT encoded in this CSI
% report change. They must not reach the gNB scheduler through a side door.
referenceState=state;
referenceState.PendingCSITable.SINR_dB(1)=80;
referenceState.PendingCSITable.CRCPass(1)=1;
referenceState.PendingCSITable.SubbandSINRVector_dB(1)="80,80";
referenceState.PendingCSITable.PostEqSINRPerLayer_dB(1)="80,80";
referenceResult=sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHUCIRuntime(referenceState,out);
state=sixgr.truth.CoupledTruthRuntime.applyDecodedPUSCHUCIRuntime(state,out);
fprintf('CSI_WIRE_ONLY_AUTHORITY measured_reference_sinr=%g changed_reference_sinr=%g receiver_cqi=%g/%g\n', ...
    state.LatestDLFeedback(1).SINR_dB,referenceResult.LatestDLFeedback(1).SINR_dB, ...
    state.LatestDLFeedback(1).CQI,referenceResult.LatestDLFeedback(1).CQI);
assert(isequaln(state.LatestDLFeedback,referenceResult.LatestDLFeedback), ...
    'Unreported UE SINR/source CRC must not alter scheduler feedback from identical received CSI bits.');
assert(isnan(state.LatestDLFeedback(1).SINR_dB) && isnan(state.LatestDLFeedback(1).FeedbackCRCPass), ...
    'CSI CQI/RI/PMI/CRI carries neither a measured SINR nor a data-TB CRC.');
assert(isempty(state.LatestDLFeedback(1).SubbandSINRVector_dB) && ...
    isempty(state.LatestDLFeedback(1).PostEqSINRPerLayer_dB));
audit=jsondecode(referenceResult.PendingCSITable.UEReferenceRecordJSON(1));
assert(audit.SINR_dB==80 && audit.CRCPass==1 && string(audit.SubbandSINRVector_dB)=="80,80", ...
    'UE reference measurements must remain available as audit, not scheduler inputs.');
logsRoot=fullfile(fileparts(fileparts(mfilename('fullpath'))),'logs','csi_wire_authority');
if ~isfolder(logsRoot), mkdir(logsRoot); end
outputRoot=tempname(logsRoot); mkdir(outputRoot);
path=fullfile(outputRoot,'received_csi_report.csv');
sixgr.util.csvWriteTable(path,referenceResult.PendingCSITable,'PreserveSchema',true,'RoundTripNumericText',true);
saved=sixgr.util.csvReadTable(path,'TextType','string');
savedAudit=jsondecode(saved.UEReferenceRecordJSON(1));
assert(isnan(saved.SINR_dB(1)) && isnan(saved.CRCPass(1)) && savedAudit.SINR_dB==80 && savedAudit.CRCPass==1);
fprintf('CSI_RECEIVED_FIELD_AUDIT_CSV_PASS root=%s\n',outputRoot);
assert(state.PendingCSITable.CSIUCIDecodeOk(1) && state.PendingCSITable.Processed(1));
assert(string(state.PendingCSITable.CSIUCITransport(1))=="pusch_decoded");
decoded=config.decode(received.DecodedCSIPart1,received.DecodedCSIPart2);
assert(state.PendingCSITable.RI(1)==decoded.RI && state.PendingCSITable.PMI(1)==decoded.PMI);
trace=state.PUCCHGrantTraceTable;
hit=string(trace.PUCCHGrantId)=="PUCCH-CSI-"+string(state.PendingCSITable.ReportIdentity(1));
assert(nnz(hit)==1 && trace.PUSCHUCIDecodeOk(hit) && ~trace.UCIContentMatch(hit), ...
    'Received CSI must be usable without masking the poisoned diagnostic reference.');
fprintf('PUSCH_RECEIVED_CSI_SCHEDULER_AUTHORITY_PASS\n');
end

function llr=localPUSCHLLR(p,bits)
% One-bit UCI contains x/y placeholders. They must pass through actual
% scrambling/modulation, not be interpreted as binary hard-decision LLRs.
carrier=nrCarrierConfig;
symbols=nrPUSCH(carrier,p,bits);
llr=nrPUSCHDecode(carrier,p,symbols,.01);
end

