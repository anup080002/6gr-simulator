function ok = testPDSCHReceiverCDL()
%TESTPDSCHRECEIVERCDL Concrete CDL-C production truth receiver evidence.

setup6GRSimToolkit("Verbose",false);
probe = sixgr.pdsch.PDSCHCoverageExecutor.runReceiverTruthPoint( ...
    "CDL-C","Rank",1,"Modulation","QPSK", ...
    "SNRdB",55,"Seed",11,"NumTrials",1);

assert(probe.Passed && probe.Trials == 1, ...
    "CDL-C truth receiver point did not pass.");
assert(probe.TBErrors == 0 && probe.BLER == 0, ...
    "High-SNR CDL-C truth point must recover the transport block.");
assert(string(probe.ConcreteProfile) == "CDL-C" ...
    && string(probe.ChannelModel) == "CDL-C", ...
    "CDL receiver evidence must preserve the concrete profile.");
assert(contains(string(probe.ChannelEstimateScope),"resource_selective"), ...
    "CDL receiver must use a resource-selective estimate.");
assert(~contains(lower(string(probe.ChannelEstimateSource)), ...
    ["scalar","fallback","proxy","unit_channel"]), ...
    "CDL receiver evidence contains a prohibited estimate source.");
assert(string(probe.ExecutionBackend) == ...
    "PDSCHTransmitter>38.901_channel>PDSCHReceiver", ...
    "CDL evidence must come from the single canonical explicit chain.");
assert(all(string(probe.TrialTable.ExecutionBackend) == ...
    probe.ExecutionBackend) ...
    && all(string(probe.TrialTable.ChannelObjectClass) == ...
        "nrCDLChannel") ...
    && all(string(probe.TrialTable.ChannelEstimateSource) == ...
        "nrChannelEstimate"), ...
    "CDL trial provenance is not canonical end-to-end evidence.");
assert(all(contains(string( ...
    probe.TrialTable.ChannelEstimateNMSESource), ...
    "not_true_channel_oracle")) ...
    && all(isfinite(probe.TrialTable.NMSE_dB)), ...
    "CDL estimator residual must be finite and explicitly non-oracle.");
assert(all(logical(probe.TrialTable.ChannelEstimateAvailable)) ...
    && all(logical(probe.TrialTable.EqualizationAvailable)) ...
    && all(logical(probe.TrialTable.DLSCHDecodeAvailable)) ...
    && all(logical(probe.TrialTable.LLRFinite)), ...
    "CDL truth point is missing production receiver-stage evidence.");

fprintf("PDSCH CDL truth receiver: BLER %.3f, SINR %.2f dB\n", ...
    probe.BLER,probe.MeasuredSINRdB);
ok = true;
end
