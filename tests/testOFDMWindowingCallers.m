function ok = testOFDMWindowingCallers()
%TESTOFDMWINDOWINGCALLERS Guard canonical zero-windowing at waveform callers.

setup6GRSimToolkit("Verbose", false);

carrier = nrCarrierConfig;
carrier.NCellID = 17;
carrier.NSizeGrid = 24;
carrier.NStartGrid = 0;
carrier.SubcarrierSpacing = 30;
carrier.CyclicPrefix = "normal";
carrier.NSlot = 0;
grid = complex(zeros(12 * carrier.NSizeGrid, carrier.SymbolsPerSlot));
grid(1, 1) = 1 + 1j;
grid(end, end) = -1 + 1j;
grid(floor(end / 2), 7) = 1 - 1j;

[implicitWaveform, implicitInfo] = ...
    sixgr.phy.waveform.ofdmModulate(carrier, grid);
[zeroWaveform, zeroInfo] = sixgr.phy.waveform.ofdmModulate( ...
    carrier, grid, "Windowing", 0);
directZero = nrOFDMModulate(carrier, grid, "Windowing", 0);
assert(isequal(implicitWaveform, zeroWaveform) && ...
    isequal(implicitWaveform, directZero), ...
    "Wrapper omission must produce exactly the explicit zero-window waveform.");
assert(double(implicitInfo.Windowing) == 0 && ...
    double(implicitInfo.OFDMWindowingSamples) == 0 && ...
    string(implicitInfo.OFDMWindowingSource) == ...
        "standard_default_zero" && ...
    double(implicitInfo.OFDMSamplingResolution.WindowingSamples) == 0, ...
    "Wrapper omission must record canonical zero windowing.");
assert(double(zeroInfo.Windowing) == 0 && ...
    string(zeroInfo.OFDMWindowingSource) == ...
        "explicit_windowing_samples", ...
    "Explicit zero must remain distinguishable from the standard default.");

[recoveredGrid, demodInfo] = ...
    sixgr.phy.waveform.ofdmDemodulate(carrier, implicitWaveform);
assert(isequal(size(recoveredGrid), size(grid)) && ...
    max(abs(recoveredGrid(:) - grid(:))) <= 1e-12, ...
    "Canonical OFDM demodulation must recover the zero-windowing grid.");
assert(double(demodInfo.OFDMSamplingResolution.Nfft) == ...
    double(implicitInfo.OFDMSamplingResolution.Nfft) && ...
    double(demodInfo.OFDMSamplingResolution.SampleRateHz) == ...
    double(implicitInfo.OFDMSamplingResolution.SampleRateHz) && ...
    double(demodInfo.OFDMSamplingResolution.WindowingSamples) == 0 && ...
    double(demodInfo.NoiseTransform.Windowing) == 0, ...
    "Modulation and demodulation must share one validated OFDM policy.");

[oneSampleWaveform, oneSampleInfo] = ...
    sixgr.phy.waveform.ofdmModulate( ...
        carrier, grid, "Windowing", 1);
directOneSample = nrOFDMModulate( ...
    carrier, grid, "Windowing", 1);
assert(isequal(oneSampleWaveform, directOneSample) && ...
    double(oneSampleInfo.Windowing) == 1 && ...
    double(oneSampleInfo.OFDMWindowingSamples) == 1, ...
    "An explicit nonzero windowing setting must be applied exactly.");
assert(size(oneSampleWaveform, 1) == size(implicitWaveform, 1), ...
    "Explicit windowing must not alter the slot sample count.");

localAssertThrows(@() sixgr.phy.waveform.ofdmModulate( ...
    carrier, grid, "Windowing", -1), ...
    "sixgr:phy:frame:InvalidWindowingSamples");
localAssertThrows(@() sixgr.phy.waveform.ofdmModulate( ...
    carrier, grid, "Windowing", 0, "Windowing", 0), ...
    "sixgr:phy:ofdmModulate:DuplicateOption");
localAssertThrows(@() sixgr.phy.waveform.ofdmDemodulate( ...
    carrier, implicitWaveform, "Nfft", 128), ...
    "sixgr:phy:frame:OFDMAliasing");
localAssertThrows(@() sixgr.phy.waveform.ofdmDemodulate( ...
    carrier, implicitWaveform, "Nfft", ...
    implicitInfo.Nfft, "Nfft", implicitInfo.Nfft), ...
    "sixgr:phy:ofdmDemodulate:DuplicateOption");

srsCfg = sixgr.phy.srs.buildSRSConfigFromScenario( ...
    localSRSConfig(0), ...
    "RunFolder", tempdir, ...
    "RunId", "ofdm_windowing_srs_zero", ...
    "ScenarioName", "ofdm_windowing_srs_zero");
srsTx = sixgr.phy.srs.generateSRSWaveform(srsCfg);
assert(double(srsTx.OFDMWindowingSamples) == 0 && ...
    double(srsTx.OFDMInfo.Windowing) == 0 && ...
    double(srsTx.OFDMSamplingResolution.WindowingSamples) == 0, ...
    "Strict SRS waveform generation must use canonical zero windowing.");

multiUE = sixgr.phy.srs.generateMultiUESRSGrid( ...
    srsCfg, 1, "Mode", "orthogonal", "SNRdB", 45, "Seed", 24681);
assert(double(multiUE.OFDMWindowingSamples) == 0 && ...
    double(multiUE.CompositeOFDMInfo.Windowing) == 0 && ...
    double(multiUE.OFDMSamplingResolution.WindowingSamples) == 0, ...
    "Multi-UE SRS composite generation must use the same zero-windowing policy.");

explicitSRSConfig = localSRSConfig(1);
explicitSRS = sixgr.phy.srs.buildSRSConfigFromScenario( ...
    explicitSRSConfig, ...
    "RunFolder", tempdir, ...
    "RunId", "ofdm_windowing_srs_explicit", ...
    "ScenarioName", "ofdm_windowing_srs_explicit");
explicitSRSTx = sixgr.phy.srs.generateSRSWaveform(explicitSRS);
assert(double(explicitSRSTx.OFDMWindowingSamples) == 1 && ...
    double(explicitSRSTx.OFDMInfo.Windowing) == 1, ...
    "Strict SRS generation must honor an explicit implementation setting exactly.");

ok = true;
end

function cfg = localSRSConfig(windowingSamples)
cfg = struct();
cfg.run.seed = 24680;
cfg.channel.model = "AWGN";
cfg.channel.snr_dB = 45;
cfg.phy.carrier.NCellID = 17;
cfg.phy.carrier.NSizeGrid = 24;
cfg.phy.carrier.NStartGrid = 0;
cfg.phy.numerology.scs_kHz = 30;
cfg.phy.numerology.cyclicPrefix = "normal";
cfg.phy.frameStructure.DuplexMode = "FDD";
cfg.phy.srs.enable = true;
cfg.phy.srs.nPorts = 1;
cfg.phy.srs.bandwidthRB = 24;
cfg.phy.ofdm.windowingSamples = double(windowingSamples);
cfg.lls6g.reference_signals.srs.coverage_requirement = ...
    "configured_band";
cfg.lls6g.reference_signals.srs.full_carrier_sounding_required = false;
cfg.lls6g.reference_signals.srs.slot_numbers = 0;
cfg.lls6g.reference_signals.srs.low_snr_sweep_db = 45;
cfg.lls6g.reference_signals.srs.timing_offset_sweep_samples = 0;
end

function localAssertThrows(fn, expectedID)
try
    fn();
catch cause
    assert(strcmp(cause.identifier, expectedID), ...
        "Expected error %s, received %s (%s).", ...
        expectedID, cause.identifier, cause.message);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.", expectedID);
end
