function ok = testLLSAntennaRuntimeEvidence()
%TESTLLSANTENNARUNTIMEEVIDENCE Verify active LLS BS/UE antenna objects reach DL/UL runtime trials and exports.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
c = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

[cfg, state, grant] = localPrepareRuntime(tmp);

resolvedT = state.AntennaConfigResolvedTable;
assert(istable(resolvedT) && height(resolvedT) >= 2, ...
    "Runtime initialization must create resolved BS/UE antenna evidence rows.");
assert(any(strcmpi(string(resolvedT.NodeType), "BS")) && any(strcmpi(string(resolvedT.NodeType), "UE")), ...
    "Runtime antenna evidence must include both BS and UE entries.");
assert(any(double(resolvedT.NumElements(strcmpi(string(resolvedT.NodeType), "BS"))) == double(cfg.phy.nTxAnt)), ...
    "BS runtime antenna evidence must preserve the configured transmit-antenna count.");
assert(any(double(resolvedT.NumElements(strcmpi(string(resolvedT.NodeType), "UE"))) == double(cfg.phy.nRxAnt)), ...
    "UE runtime antenna evidence must preserve the configured receive-antenna count.");

[cfgDL, state] = sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg, state, 1, "DL");
[cfgUL, state] = sixgr.truth.CoupledTruthRuntime.applyUserContext(cfg, state, 1, "UL");
cfgDL = localApplyStrictPDSCHFixture(cfgDL);
cfgUL = localApplyStrictPDSCHFixture(cfgUL);
assert(isstruct(cfgDL.lls6g.userContext.RuntimeServingBSAntenna) && ...
    ~isempty(fieldnames(cfgDL.lls6g.userContext.RuntimeServingBSAntenna)), ...
    "DL runtime user context must carry the active BS antenna object.");
assert(isstruct(cfgDL.lls6g.userContext.RuntimeUEAntenna) && ...
    ~isempty(fieldnames(cfgDL.lls6g.userContext.RuntimeUEAntenna)), ...
    "DL runtime user context must carry the active UE antenna object.");
assert(isstruct(cfgUL.lls6g.userContext.RuntimeServingBSAntenna) && ...
    isstruct(cfgUL.lls6g.userContext.RuntimeUEAntenna), ...
    "UL runtime user context must carry the active BS/UE antenna objects.");

dl = sixgr.link.runDLPDSCHThroughput(cfgDL, ...
    "NumFrames", 1, ...
    "SNR_dB", cfg.channel.snr_dB, ...
    "InterferenceBundle", struct([]));
ul = sixgr.link.runULPUSCHThroughput(cfgUL, ...
    "NumFrames", 1, ...
    "SNR_dB", cfg.channel.snr_dB, ...
    "InterferenceBundle", struct([]));

localAssertRawAntennaEvidence(dl.TrialTable, "DL", cfg);
localAssertRawAntennaEvidence(ul.TrialTable, "UL", cfg);

rawTrials = struct("DL", dl.TrialTable, "UL", ul.TrialTable);
mobilityArtifacts = sixgr.truth.CoupledTruthRuntime.mobilityArtifacts(state);
artifacts = sixgr.truth.exportLLSLiveDerivedTables(cfg, fullfile(tmp, "run"), rawTrials, struct(), mobilityArtifacts, struct("AntennaConfigResolvedTable", resolvedT));

antennaConfigT = readtable(char(artifacts.AntennaConfigResolvedPath), "VariableNamingRule", "preserve", "Delimiter", ",");
antennaRuntimeT = readtable(char(artifacts.AntennaRuntimeEvidencePath), "VariableNamingRule", "preserve", "Delimiter", ",");
consistencyT = readtable(char(artifacts.ChannelArrayConsistencyPath), "VariableNamingRule", "preserve", "Delimiter", ",");

assert(height(antennaConfigT) >= 2, ...
    "Resolved antenna config export must preserve runtime BS/UE rows.");
assert(height(antennaRuntimeT) == 2, ...
    "Antenna runtime evidence export must preserve the active DL and UL trial rows.");
assert(all(logical(antennaRuntimeT.AntennaRuntimeObjectCreated)), ...
    "Antenna runtime evidence export must disclose successful runtime object creation.");
assert(all(strlength(string(antennaRuntimeT.AntennaConfigSource)) > 0) && ...
    all(strlength(string(antennaRuntimeT.RuntimeAntennaObjectSource)) > 0), ...
    "Antenna runtime evidence export must disclose config and runtime object sources.");
assert(height(consistencyT) == 2 && all(strcmpi(string(consistencyT.ChannelArrayModel), "nrtdl_runtime_geometry_correlation_channel")), ...
    "Array consistency export must disclose the active reduced geometry-correlation TDL model for both DL and UL.");
assert(all(strcmpi(string(consistencyT.ChannelObjectSource), "sixgr.channel.channelfactory.localcreatetdl")) && ...
    all(strcmpi(string(consistencyT.ChannelObjectClass), "nrtdlchannel")) && ...
    all(strcmpi(string(consistencyT.ChannelArrayHandlingStatus), "adapted_geometry_backed_reduced_representation")) && ...
    all(strcmpi(string(consistencyT.ChannelArrayHandlingBlocker), "nrtdlchannel_consumes_custom_spatial_correlation_matrices_not_runtime_array_objects")) && ...
    all(strcmpi(string(consistencyT.ChannelGeometryCouplingLevel), "runtime_geometry_reduced_spatial_correlation")) && ...
    all(strcmpi(string(consistencyT.GeometryAdapterType), "tdl_custom_tx_rx_correlation_from_runtime_element_positions")), ...
    "Array consistency export must preserve the active TDL channel-object source and reduced geometry adapter evidence.");
assert(all(~logical(consistencyT.ChannelUsesCountOnlyAntennaModel)), ...
    "Array consistency export must not keep reporting count-only TDL when the runtime geometry adapter is active.");
assert(all(~logical(consistencyT.ChannelUsesSameRuntimeAntennaAssumptions)), ...
    "Array consistency export must not claim that reduced TDL correlation matrices equal full runtime antenna-object coupling.");
requiredConsistencyVars = { ...
    'ConfiguredTxPhysicalElements','ConfiguredRxPhysicalElements', ...
    'ObservedTxWaveformColumns','ObservedPhysicalTxAntennas','ObservedPhysicalRxAntennas', ...
    'PhysicalTxConsistencyRate','PhysicalRxConsistencyRate','PhysicalArrayConsistencyOk', ...
    'LogicalPhysicalDomainSeparated','LegacyPortConsistencyApplicable'};
assert(all(ismember(requiredConsistencyVars, consistencyT.Properties.VariableNames)), ...
    "Array consistency export must separate logical PHY ports from physical array dimensions.");
assert(all(double(consistencyT.PhysicalTxConsistencyRate) == 1) && ...
    all(double(consistencyT.PhysicalRxConsistencyRate) == 1) && ...
    all(logical(consistencyT.PhysicalArrayConsistencyOk)), ...
    "DL and UL physical waveform dimensions must exactly match the configured physical arrays.");
assert(all(contains(string(consistencyT.Notes), "runtime-geometry-backed reduced TDL representation")) && ...
    all(contains(string(consistencyT.Notes), "custom Tx/Rx spatial correlation matrices")), ...
    "Array consistency export notes must explain the reduced TDL geometry adapter boundary.");

ok = true;
end

function localAssertRawAntennaEvidence(T, direction, cfg)
assert(istable(T) && height(T) == 1, ...
    "Expected one raw %s trial row for antenna runtime validation.", direction);
requiredVars = { ...
    'BSAntennaArrayClass','BSAntennaElementClass','BSAntennaArrayType','BSAntennaRows','BSAntennaCols','BSAntennaElements','BSAntennaPolarization','BSAntennaAzimuth_deg','BSAntennaNumPorts', ...
    'UEAntennaArrayClass','UEAntennaElementClass','UEAntennaArrayType','UEAntennaRows','UEAntennaCols','UEAntennaElements','UEAntennaPolarization','UEAntennaHeading_deg','UEAntennaNumPorts', ...
    'ConfiguredTxAntennas','ConfiguredRxAntennas','TxWaveformColumns','PhysicalTxAntennas','NumRxAntennas', ...
    'AntennaConfigSource','RuntimeAntennaObjectSource','AntennaRuntimeObjectCreated','ChannelArrayModel','ChannelObjectSource','ChannelObjectClass','ChannelArrayHandlingStatus','ChannelArrayHandlingBlocker','ChannelGeometryCouplingLevel','GeometryAdapterType','GeometryAdapterSource','GeometryAdapterLimitation','GeometryAdapterPortMapping','ChannelUsesCountOnlyAntennaModel','ChannelUsesSameRuntimeAntennaAssumptions','InterferenceChannelObjectSource','InterferenceChannelObjectClass','InterferenceChannelArrayHandlingStatus','InterferenceChannelArrayHandlingBlocker','InterferenceUsesSameRuntimeAntennaAssumptions','InterferencePathUsesSameArrayAssumptions', ...
    'PropagationDistance_m','GeometricPropagationDelay_s','PropagationDelay_s','ToD_s','ToA_s','ChannelDelaySource','AntennaGeometrySource','RuntimeTraceSource','SameFlowEvidenceSource'};
assert(all(ismember(requiredVars, T.Properties.VariableNames)), ...
    "Raw %s trial row must expose active antenna runtime evidence.", direction);
assert(logical(T.AntennaRuntimeObjectCreated(1)), ...
    "Raw %s trial row must confirm runtime antenna object creation.", direction);
assert(strcmpi(char(string(T.AntennaConfigSource(1))), "browser_yaml_to_buildinternalconfig_to_coupledtruthruntime"), ...
    "Raw %s trial row must disclose the browser/YAML-to-runtime antenna source.", direction);
assert(isfinite(double(T.BSAntennaElements(1))) && double(T.BSAntennaElements(1)) == double(cfg.phy.nTxAnt), ...
    "Raw %s trial row must preserve the configured BS antenna count.", direction);
assert(isfinite(double(T.UEAntennaElements(1))) && double(T.UEAntennaElements(1)) == double(cfg.phy.nRxAnt), ...
    "Raw %s trial row must preserve the configured UE antenna count.", direction);
assert(isfinite(double(T.BSAntennaAzimuth_deg(1))) && isfinite(double(T.UEAntennaHeading_deg(1))), ...
    "Raw %s trial row must preserve runtime BS azimuth and UE heading.", direction);
assert(double(T.TxWaveformColumns(1)) == double(T.ConfiguredTxAntennas(1)) && ...
    double(T.PhysicalTxAntennas(1)) == double(T.ConfiguredTxAntennas(1)), ...
    "Raw %s trial row must preserve the actual physical transmit waveform dimension.", direction);
if strcmpi(direction, "UL")
    assert(ismember('RxWaveformBranches', T.Properties.VariableNames) && ...
        ismember('PhysicalRxAntennas', T.Properties.VariableNames) && ...
        double(T.RxWaveformBranches(1)) == double(T.ConfiguredRxAntennas(1)) && ...
        double(T.PhysicalRxAntennas(1)) == double(T.ConfiguredRxAntennas(1)), ...
        "Raw UL trial row must preserve the actual physical receive waveform dimension.");
end
assert(strcmpi(char(string(T.ChannelArrayModel(1))), "nrtdl_runtime_geometry_correlation_channel") && ~logical(T.ChannelUsesCountOnlyAntennaModel(1)), ...
    "Raw %s trial row must honestly disclose the active reduced geometry-correlation TDL channel model.", direction);
assert(strcmpi(char(string(T.ChannelObjectSource(1))), "sixgr.channel.channelfactory.localcreatetdl") && ...
    strcmpi(char(string(T.ChannelObjectClass(1))), "nrtdlchannel") && ...
    strcmpi(char(string(T.ChannelArrayHandlingStatus(1))), "adapted_geometry_backed_reduced_representation") && ...
    strcmpi(char(string(T.ChannelArrayHandlingBlocker(1))), "nrtdlchannel_consumes_custom_spatial_correlation_matrices_not_runtime_array_objects") && ...
    strcmpi(char(string(T.ChannelGeometryCouplingLevel(1))), "runtime_geometry_reduced_spatial_correlation") && ...
    strcmpi(char(string(T.GeometryAdapterType(1))), "tdl_custom_tx_rx_correlation_from_runtime_element_positions"), ...
    "Raw %s trial row must disclose the actual channel-object source and reduced TDL geometry adapter boundary.", direction);
assert(~logical(T.ChannelUsesSameRuntimeAntennaAssumptions(1)), ...
    "Raw %s trial row must not claim that reduced TDL correlation matrices equal full runtime antenna-object coupling.", direction);
assert(~logical(T.InterferencePathUsesSameArrayAssumptions(1)) && ...
    ~logical(T.InterferenceUsesSameRuntimeAntennaAssumptions(1)) && ...
    strlength(string(T.InterferenceChannelArrayHandlingStatus(1))) == 0, ...
    "Raw %s trial row must keep interference-channel array-truth fields empty when no interferer channel was active.", direction);
assert(isfinite(double(T.PropagationDistance_m(1))) && double(T.PropagationDistance_m(1)) > 0, ...
    "Raw %s trial row must export a finite same-flow propagation distance.", direction);
assert(isfinite(double(T.ToD_s(1))) && isfinite(double(T.ToA_s(1))) && double(T.ToA_s(1)) >= double(T.ToD_s(1)), ...
    "Raw %s trial row must export a finite same-flow ToD/ToA pair.", direction);
end

function cfg = localApplyStrictPDSCHFixture(cfg)
% This focused antenna/channel test is an isolated PHY calibration, not a
% connected PDCCH-owned scheduling campaign. Label that boundary explicitly.
cfg.phy.pdsch.executionProfile = "phy_calibration";
cfg.phy.pusch.executionProfile = "phy_calibration";
cfg.phy.pdsch.symbolAllocation = [0 14];
cfg.phy.pdsch.mappingType = "A";
cfg.phy.pusch.symbolAllocation = [0 14];
cfg.phy.pusch.mappingType = "A";
prbSet = 0:(double(cfg.phy.carrier.NSizeGrid) - 1);
cfg.phy.pdsch.prbSet = prbSet;
cfg.phy.pusch.prbSet = prbSet;
% Preserve the scenario's reference_signals.ptrs_enabled authority.  This
% fixture changes only scheduling/allocation details needed by the isolated
% antenna calibration; it must not silently disable a YAML-enabled signal.
cfg.phy.pdsch.UECapability1024QAM = false;
cfg.phy.pdsch.UECapability1024QAMVariant = "not_supported";
cfg.phy.pdsch.RRCEnabled1024QAM = false;
cfg.phy.pdsch.DCIEnabled1024QAM = false;
cfg.phy.pdsch.DeploymentAllows1024QAM = false;
cfg.phy.pdsch.FrequencyRangeAllows1024QAM = false;
cfg.phy.pdsch.BandAllows1024QAM = false;
cfg.phy.pdsch.FrequencyRange = "FR1";
cfg.phy.pdsch.OperatingBand = "n28";
cfg.phy.pdsch.DeploymentClass = "antenna_runtime_calibration";
cfg.phy.pdsch.dmrs.DMRSTypeAPosition = 3;
cfg.phy.pdsch.dmrs.typeAPosition = 3;
cfg.phy.pdsch.dmrs.typeApos = 3;
cfg.phy.dmrs.typeAPosition = 3;
cfg.phy.csirs.enable = true;
cfg.phy.csirs.nPorts = 1;
cfg.phy.csirs.rowNumber = 2;
cfg.phy.csirs.symbolLocations = 5;
cfg.phy.csirs.subcarrierLocations = 0;
cfg.phy.csirs.rbOffset = 0;
cfg.phy.csirs.numRB = max(1, min(double(cfg.phy.carrier.NSizeGrid), 24));
end
function [cfg, state, grant] = localPrepareRuntime(tmp)
