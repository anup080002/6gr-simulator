    "GrantReason", "antenna_runtime_unit_test", ...
    "Frame", 1, ...
    "Slot", 2, ...
    "HARQ", struct(), ...
    "PBCHGatingActive", true, ...
    "PRACHGatingActive", true, ...
    "PDCCHGatingActive", true, ...
    "SRSGatingActive", true, ...
