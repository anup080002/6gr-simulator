function ok = testFRCPDSCHCFOTracking()
%TESTFRCPDSCHCFOTRACKING Guard measured CFO acquisition in the DL FRC chain.

% TS 38.101-4 ATG reference points include a nonzero frequency offset.
% The offset is physically applied to the waveform.  This regression proves
% that the receiver estimates it from PDSCH DM-RS and corrects the received
% waveform before decoding; it must never reuse the configured impairment
% value as an oracle.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);

result = sixgr.conformance.runFRCPoint( ...
    "dl_r_pdsch_1_4_1_fdd_atg_awgn", "atg_awgn_220hz_2x2", ...
    "SNRGrid_dB", 22.5, "ExecutionProfile", "smoke", ...
    "MinTransportBlocks", 1, "MaxTransportBlocks", 1, ...
    "BatchSize", 1, "MinimumBlockErrors", 0, ...
    "EvaluateSymmetricRegression", false, ...
    "RequireExactStandardExecution", true, ...
    "RequireExactDataChannelExecution", true, ...
    "AssertPass", false, "PrintTable", false, "Verbose", false);

assert(height(result.Sweep) == 1 && ...
    result.Sweep.TransportBlocks(1) == 1 && ...
    result.Sweep.DeliveredTransportBlocks(1) == 1 && ...
    result.Sweep.Transmissions(1) == 1, ...
    ["The deterministic 256QAM ATG FRC transport block must decode on " ...
    "its first transmission after measured CFO correction."]);

detail = result.PointDetails{1};
rx = detail.LastTransportBlockAttemptRx{1};
assert(rx.Ok && rx.CFOCorrectionApplied && ...
    rx.CFOEstimateStatus == "available", ...
    "The PDSCH receiver did not apply an available measured CFO estimate.");
assert(rx.CFOEstimateSource == ...
    "pdsch_dmrs_reference_symbol_phase_slope", ...
    ["The FRC receiver must derive CFO from received PDSCH DM-RS; " ...
    "configured impairment values are not receiver truth."]);
assert(isfinite(rx.EstimatedCFO_Hz) && ...
    abs(rx.EstimatedCFO_Hz - 220) <= 10, ...
    "Measured CFO %.6f Hz is inconsistent with the injected 220 Hz offset.", ...
    rx.EstimatedCFO_Hz);
assert(isfinite(rx.ResidualCFO_Hz) && ...
    abs(rx.ResidualCFO_Hz) < abs(rx.EstimatedCFO_Hz) && ...
    abs(rx.ResidualCFO_Hz) <= 15, ...
    ["Post-correction residual CFO %.6f Hz does not prove effective " ...
    "receiver correction."], rx.ResidualCFO_Hz);
assert(~detail.ProxyUsed && ~detail.FallbackUsed && ...
    ~detail.TruthUnavailableRescueUsed, ...
    "The CFO regression must remain an actual waveform truth execution.");

ok = true;
end
