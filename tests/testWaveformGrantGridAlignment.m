function ok = testWaveformGrantGridAlignment()
%TESTWAVEFORMGRANTGRIDALIGNMENT Oversized system grants must align replay carrier grid.

setup6GRSimToolkit("Verbose", false);

cfg = sixgr.config.defaultConfig();
cfg.run.strictMode = true;
cfg.run.useMex = false;
cfg.outputs.saveCSV = false;
cfg.outputs.saveMAT = false;
cfg.outputs.saveFigures = false;
cfg.outputs.saveFIG = false;

% Use a standards-valid 20 MHz / 30 kHz / 51 PRB carrier tuple.  The
% oversized grant below remains intentionally larger than this carrier so
% the replay-alignment behavior under test is unchanged.
cfg.frequency.bandwidth_hz = 20e6;
cfg.channel.bandwidth_Hz = 20e6;
cfg.phy.channelBandwidth_MHz = 20;
cfg.channel.subcarrierSpacing_kHz = 30;
cfg.phy.carrier.SubcarrierSpacing = 30;
cfg.phy.carrier.NSizeGrid = 51;
cfg.phy.pdsch.modulation = "QPSK";
cfg.phy.pdsch.codeRate = 0.35;
cfg.phy.pdsch.numLayers = 1;
cfg.phy.pdsch.nLayers = 1;
cfg.phy.pdcch.symbolAllocation = [0 2];
cfg.phy.pdsch.symbolAllocation = [2 12];
cfg.phy.pdsch.mappingType = "A";

cfg.channel.awgnOnly = false;
cfg.channel.model = "TDL-C";
cfg.channel.delayProfile = "TDL-C";
cfg.channel.tdlProfile = "TDL-C";
cfg.channel.fading.enable = true;
cfg.channel.fading.model = "TDL";
cfg.channel.fading.profile = "TDL-C";
cfg.channel.fading.maxDoppler_Hz = 30;
cfg.channel.dopplerHz = 30;
cfg.channel.doppler_Hz = 30;

cfg = sixgr.config.normalizeConfig(cfg);
sixgr.config.validateConfig(cfg);

grant = struct( ...
    "RNTI", 1, ...
    "PRBSet", 0:91, ...
    "SymbolAllocation", [0 14], ...
    "MappingType", "A", ...
    "Modulation", "QPSK", ...
    "NumLayers", 1, ...
    "RV", 0, ...
    "TargetCodeRate", 0.35);

replay = sixgr.system.waveform.replayGrant(cfg, "DL", grant, [], 45, ...
    "StrictMode", true, ...
    "CompactPHYIO", true, ...
    "FastAWGNPath", false);

assert(isstruct(replay), "Waveform replay must return a struct.");
assert(isfinite(double(replay.TransportBlockSize)) && double(replay.TransportBlockSize) > 0, ...
    "Oversized grants must still produce a valid waveform transport block size.");
assert(logical(replay.UsedFading), "TDL-C waveform replay should keep fading enabled.");
assert(strcmpi(char(string(replay.ExecutionBackend)), "WAVEFORM_GRANT_REPLAY"), ...
    "Waveform replay must preserve truthful execution-backend metadata.");

cfgSystem = cfg;
cfgSystem.channel.awgnOnly = true;
cfgSystem.channel.model = "AWGN";
cfgSystem.channel.fading.enable = false;
cfgSystem.system.phyBackend = "waveform";
cfgSystem.scenario.layout.nSites = 1;
cfgSystem.scenario.layout.nSectorsPerSite = 1;
cfgSystem.scenario.layout.wrapAround = false;
cfgSystem.scenario.ue.nUE = 2;
cfgSystem.scenario.nUE = 2;
cfgSystem = sixgr.config.normalizeConfig(cfgSystem);
sixgr.config.validateConfig(cfgSystem);
cfgSystem = withCanonicalSchedulerTiming(cfgSystem);

ctx = sixgr.core.SimContext(cfgSystem);
offeredDL = repmat(2e5, 4, 2);
res = sixgr.system.SystemLevelRunner.run(ctx, struct( ...
    "NumTTI", 4, ...
    "OfferedBitsDL", offeredDL, ...
    "OfferedBitsUL", zeros(4,2), ...
    "PHYBackend", "waveform"));

assert(res.Ok, "Waveform-backed system run should complete after grid alignment.");
assert(isfield(res, "Details") && isfield(res.Details, "SchedulerGrants"), ...
    "System details must expose scheduler grants.");
grantTrace = res.Details.SchedulerGrants;
assert(istable(grantTrace) && height(grantTrace) > 0, ...
    "Waveform-backed system run should emit at least one real grant row.");
assert(max(double(grantTrace.PRBCount)) <= double(cfgSystem.phy.carrier.NSizeGrid), ...
    "System grant budgets must stay within the configured waveform carrier grid.");

cfgSystemTDL = cfg;
cfgSystemTDL.system.phyBackend = "waveform";
cfgSystemTDL.scenario.layout.nSites = 1;
cfgSystemTDL.scenario.layout.nSectorsPerSite = 1;
cfgSystemTDL.scenario.layout.wrapAround = false;
cfgSystemTDL.scenario.ue.nUE = 2;
cfgSystemTDL.scenario.nUE = 2;
cfgSystemTDL = sixgr.config.normalizeConfig(cfgSystemTDL);
sixgr.config.validateConfig(cfgSystemTDL);
cfgSystemTDL = withCanonicalSchedulerTiming(cfgSystemTDL);

ctxTDL = sixgr.core.SimContext(cfgSystemTDL);
resTDL = sixgr.system.SystemLevelRunner.run(ctxTDL, struct( ...
    "NumTTI", 8, ...
    "OfferedBitsDL", repmat(8e4, 8, 2), ...
    "OfferedBitsUL", repmat(4e4, 8, 2), ...
    "PHYBackend", "waveform"));

assert(resTDL.Ok, "Strict TDL-C waveform-backed system run should complete.");
assert(double(resTDL.Details.DecodeOK) > 0, ...
    "Conservative waveform-fading AMC should yield at least one successful decode.");
assert(double(resTDL.Details.DecodeOK_UL) > 0, ...
    "Strict TDL-C waveform-backed system run should yield at least one successful UL decode.");
assert(double(resTDL.KPITable.Throughput_Mbps(1)) > 0, ...
    "Strict TDL-C waveform-backed system run should achieve nonzero throughput.");

cfgLayout = sixgr.config.defaultConfig();
cfgLayout.scenario.layout.nSites = 20;
cfgLayout.scenario.layout.nSectorsPerSite = 3;
layout = sixgr.scenario.generateLayout(cfgLayout);
assert(size(layout.sites.pos_m, 1) == 20, ...
    "Hex layout generator must materialize all requested sites.");
assert(size(layout.bs.pos_m, 1) == 60, ...
    "Hex layout generator must materialize all requested sectors/cells.");

tmpRoot = fullfile(tempdir, "sixgr_waveform_truth_campaign_test");
if isfolder(tmpRoot)
    rmdir(tmpRoot, "s");
end
cfgCampaign = cfgSystem;
cfgCampaign.scenario.ue.nUE = 4;
cfgCampaign.scenario.nUE = 4;
rep = sixgr_run_3gpp_full_campaign(cfgCampaign, ...
    "ResultsRoot", tmpRoot, ...
    "CampaignProfileMode", "waveform_system_truth_experimental", ...
    "CampaignProfileEntryPoint", "testWaveformGrantGridAlignment", ...
    "RunLinkCampaign", false, ...
    "RunDetailedLinkDiagnostics", false, ...
    "SystemDuration_s", 0.01, ...
    "SystemNumUE", 4, ...
    "RunSystemMMTCProbe", false, ...
    "RunAuxiliaryProbes", false, ...
    "RunE2EStackProbe", false, ...
    "UseFastLinkModel", false, ...
    "UseMexAcceleration", false, ...
    "UseParallelAcceleration", false, ...
    "AutoStartParallelPool", false, ...
    "AutoBuildMexAcceleration", false, ...
    "CalibrateSystemBLERFromLink", false, ...
    "GenerateCampaignPlots", false, ...
    "VerifyArtifacts", false, ...
    "OrganizeByBlock", false, ...
    "Verbose", false);

manifest = jsondecode(fileread(char(rep.Summary.MetaRunManifestJSON)));
assert(strcmpi(char(string(manifest.E2EAirModel)), "not_run"), ...
    "Manifest must mark E2EAirModel as not_run when E2E did not execute.");
assert(~isfield(manifest, "CalibrationSource"), ...
    "Unused calibration provenance must not be exported for waveform-only system campaigns.");
assert(~isfile(fullfile(char(rep.RunFolder), "meta", "calibration_source.json")), ...
    "Unused calibration metadata JSON must not be written.");

audit = readtable(char(rep.Summary.AuditCSV), "VariableNamingRule", "preserve");
row = audit(strcmp(string(audit.Category), "15. Multi-User and Multi-Cell Metrics"), :);
assert(height(row) == 1 && strcmpi(char(string(row.Status)), "implemented"), ...
    "Waveform-backed system KPIs must not be labeled as system abstraction.");
assert(~contains(lower(char(string(row.Notes))), "abstraction"), ...
    "Waveform-backed system audit notes must not claim system abstraction.");

notRunNotes = lower(join(string(audit.Notes(strcmp(string(audit.Status), "not_run"))), " | "));
assert(~contains(notRunNotes, "proxy"), ...
    "Not-run audit rows should not retain proxy wording from skipped modules.");

sysKpi = readtable(fullfile(char(rep.RunFolder), "system", "csv", "system_kpis.csv"), ...
    "VariableNamingRule", "preserve");
assert(height(sysKpi) == 1 && double(sysKpi.NumTTI(1)) > 1, ...
    "System campaign duration must expand to multiple TTIs using the configured slot duration.");
ok = true;
end
