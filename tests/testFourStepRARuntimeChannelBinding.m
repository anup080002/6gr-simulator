function ok = testFourStepRARuntimeChannelBinding()
%TESTFOURSTEPRARUNTIMECHANNELBINDING Four-step RA uses runtime channel state.
cfg = raStrictAnchorConfig();
res = sixgr.truth.CoupledTruthRuntime.runFourStepRARuntime(cfg, ...
    "RunId", "test_ra_runtime_channel", ...
    "UEId", 1, "CellId", 1, "AttemptId", 1, ...
    "RuntimeSlot", 1, "WriteArtifacts", false);

assert(logical(res.RACompleted) && logical(res.StrictOk), ...
    "Runtime-coupled four-step RA must complete Msg1-Msg4.");
assert(logical(res.RuntimeChannelStateUsed), ...
    "Runtime-coupled RA must use the persistent channel-state transport.");
assert(logical(res.RuntimeStageWaveformsUsed), ...
    "Every runtime-channel receive waveform must be disclosed as an in-chain runtime waveform.");
assert(~logical(res.RuntimeSelfLoopWaveformsUsed), ...
    "Runtime-coupled RA must not decode direct TX self-loop waveforms.");
assert(string(res.RuntimeTransportMode) == "persistent_runtime_channel_state", ...
    "Runtime transport mode must disclose persistent channel-state use.");

T = res.ArtifactTables.ra_runtime_stage_waveforms;
expectedStages = ["Msg1","Msg2","Msg3","Msg4","RRCSetupComplete"];
assert(height(T) == numel(expectedStages), ...
    "Runtime RA must publish one transport row per waveform-carried message.");
assert(isequal(string(T.StageName).', expectedStages), ...
    "Runtime RA stages must include ordered Msg1-Msg4 and RRCSetupComplete.");
assert(all(logical(T.RuntimeChannelStateUsed)) && ~any(logical(T.SelfLoopWaveformUsed)), ...
    "Every RA message must traverse the runtime channel-state path.");
assert(all(logical(T.RuntimeStageWaveformUsed)), ...
    "Every RA message must consume the receive waveform returned by the runtime channel.");
assert(all(isfinite(double(T.StageSlot))) && ...
    double(T.StageSlot(end)) == double(res.SetupCompleteScheduledSlot), ...
    "All runtime stages, including RRCSetupComplete, must have their actual scheduled slot.");
assert(logical(res.RuntimeDLChannelState.Initialized) && ...
    logical(res.RuntimeULChannelState.Initialized) && ...
    double(res.RuntimeDLChannelState.CurrentSampleIndex) > 0 && ...
    double(res.RuntimeULChannelState.CurrentSampleIndex) > 0, ...
    "RA must return the advanced DL and UL channel states for causal timeline commit.");
assert(any(contains(string(T.RuntimeChannelLinkKey), "dir=UL")) && ...
    any(contains(string(T.RuntimeChannelLinkKey), "dir=DL")), ...
    "Runtime RA must use both UL and DL persistent link keys.");
assert(all(isfinite(double(T.AppliedTxPower_dBm))) && ...
    all(abs(double(T.TxPowerClosureError_dB)) < 1e-8), ...
    "Every RA stage must close its typed YAML-derived transmit-power budget.");
assert(all(strlength(strtrim(string(T.TxPowerSource))) > 0) && ...
    all(strlength(strtrim(string(T.WaveformAmplitudeUnit))) > 0), ...
    "Every RA stage must disclose its transmit-power authority and amplitude unit.");
assert(all(logical(T.NoiseApplied)) && ...
    all(isfinite(double(T.NoiseVariance)) & double(T.NoiseVariance) > 0), ...
    "Every RA message must traverse one explicit runtime noise injection.");
assert(all(logical(T.CompositeReceiverFrontEndApplied)), ...
    "Every RA message must traverse the configured composite receiver front end.");
assert(all(strlength(strtrim(string(T.TxRFExecutionStatus))) > 0) && ...
    all(strlength(strtrim(string(T.CompositeReceiverFrontEndStatus))) > 0), ...
    "Every RA message must disclose TX and RX RF execution status.");
msg3 = T(string(T.StageName) == "Msg3", :);
setupComplete = T(string(T.StageName) == "RRCSetupComplete", :);
assert(height(msg3) == 1 && height(setupComplete) == 1 && ...
    abs(double(msg3.AppliedTxPower_dBm) - ...
        double(setupComplete.AppliedTxPower_dBm)) < 1e-9, ...
    "RRCSetupComplete must inherit the same typed UL PUSCH power authority as Msg3.");
assert(string(res.Msg3ContentionIdentity) == string(res.Msg4ContentionIdentity), ...
    "Msg4 contention identity must be decoded from the waveform and match Msg3.");
ok = true;
end
