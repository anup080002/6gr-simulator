function ok = testPDSCHFadingPRGAwareChannelEstimate()
%TESTPDSCHFADINGPRGAWARECHANNELESTIMATE Guard PRG boundary estimation.

setup6GRSimToolkit("Verbose",false,"RunToolboxChecks",false);
probe = sixgr.pdsch.PDSCHCoverageExecutor.runReceiverTruthPoint( ...
    "CDL-C", ...
    "Rank",3, ...
    "Modulation","256QAM", ...
    "SNRdB",65, ...
    "Seed",11, ...
    "NumTrials",1, ...
    "EnablePhaseNoise",false, ...
    "NumerologyKHz",60, ...
    "MappingType","A", ...
    "DMRSConfigurationType",1, ...
    "DMRSLength",1, ...
    "DMRSAdditionalPosition",3, ...
    "DMRSMultiplexing","basic", ...
    "DMRSPortSet",0:2, ...
    "PTRSEnabled",true, ...
    "PrecodingMode","prg_codebook", ...
    "RV",0, ...
    "PRBSet",0:5, ...
    "ExecutionLabel","PRG-STITCH-REGRESSION");

trial = probe.TrialTable;
assert(height(trial) == 1 && trial.CRCPass && probe.TBErrors == 0, ...
    "Rank-3 PRG-varying CDL-C truth point must decode its scheduled TBS.");
assert(startsWith(string(trial.ChannelEstimateSource), ...
    "nrChannelEstimate_prg_stitched"), ...
    "Fading PRG reception must use the PRG-aware resource-selective estimator.");
assert(trial.StrictReceiverEvidenceOk && trial.ChannelFadingApplied ...
    && trial.BitsCompared > 40 && trial.BitErrors == 0, ...
    "PRG-aware regression requires real fading, scheduled TBS, and exact decode.");
assert(trial.PostEqSINR_dB > 25 && trial.NMSE_dB < -25, ...
    "PRG-aware channel reconstruction did not remove the precoder-boundary floor.");

fprintf("PDSCH PRG-aware fading estimate: SINR %.3f dB, NMSE %.3f dB, %d bits.\n", ...
    trial.PostEqSINR_dB,trial.NMSE_dB,trial.BitsCompared);
ok = true;
end
