function ok = testLLSKPIConsistencyNotApplicableRows()
%TESTLLSKPICONSISTENCYNOTAPPLICABLEROWS Disabled KPIs are explicit, not failed.

setup6GRSimToolkit("Verbose", false);

rootDir = tempname;
mkdir(rootDir);
cleanupObj = onCleanup(@() rmdir(rootDir, "s")); %#ok<NASGU>
layout = sixgr.report.resultLayout(rootDir);
sixgr.util.ensureDir(layout.ReportCSVDir);
sixgr.util.ensureDir(layout.AirInterfaceCSVDir);

sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, "scenario_summary.csv"), ...
    table("completed", true, true, ...
    'VariableNames', {'RunCompletion','Ok','ResultOk'}));
sixgr.util.csvWriteTable(fullfile(layout.AirInterfaceCSVDir, "lls_kpi_summary.csv"), ...
    table("fixture", true, true, "pass", "", ...
    'VariableNames', {'ScenarioID','KPIReconciliationPass','StrictOk','Status','FailureReason'}));

reconT = table( ...
    ["DL_BLER"; "DL_HARQ_NACK_Rate"], ["DL"; "DL"], ...
    [true; true], [true; true], [true; false], [true; true], ...
    [false; true], ["configured_measurement_window_sec"; "unavailable"], ...
    ["pass"; "not_applicable"], [""; ""], ...
    [true; false], ["always_applicable_raw_phy_kpi"; ...
    "harq_disabled_by_resolved_configuration"], ...
    'VariableNames', {'KPIName','Direction','StrictOk','ReconciliationPass', ...
    'FormulaExecuted','SchemaValid','MissingRawData','DurationSource', ...
    'Status','FailureReason','Applicable','ApplicabilityReason'});
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, ...
    "kpi_reconstruction_summary.csv"), reconT);

names = ["Scenario_Total_UL_DeliveredBits"; ...
    "Scenario_Total_DL_DeliveredBits"; ...
    "Scenario_Total_UL_ScheduledBits"; ...
    "Scenario_Total_DL_ScheduledBits"];
bindingT = table(names, true(4,1), true(4,1), true(4,1), ...
    true(4,1), repmat("pass",4,1), ...
    'VariableNames', {'KPIName','MandatoryInScenarioObjective', ...
    'RawEvidenceAvailable','ReconstructionPass','StrictOk','Status'});
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, ...
    "kpi_objective_binding.csv"), bindingT);

scfg = struct();
scfg = sixgr.util.structSet(scfg, "scenario_id", "kpi_na_fixture");
scfg = sixgr.util.structSet(scfg, "scenario.honesty_mode", "strict");
scfg = sixgr.util.structSet(scfg, "users.execution_model", "slot_coupled_truth");
scfg = sixgr.util.structSet(scfg, "simulation.link_direction", "both");
verdict = struct("Failures", strings(0,1), ...
    "CanonicalArtifactGapCount", 0, ...
    "RequiredRuntimeEvidenceMissingCount", 0, ...
    "RoundtripMismatchCount", 0, "StrictProxyGuardFailureCount", 0);

root = sixgr.truth.evaluateStrictAnchorStatus(rootDir, scfg, struct(), ...
    verdict, localTrialRows("DL"), localTrialRows("UL"), struct());
assert(logical(root.Status.KpiConsistencyOk), ...
    "Explicit not-applicable KPI rows must not fail KPI consistency.");

reconT.ApplicabilityReason(2) = "";
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, ...
    "kpi_reconstruction_summary.csv"), reconT);
rootMissingReason = sixgr.truth.evaluateStrictAnchorStatus(rootDir, scfg, ...
    struct(), verdict, localTrialRows("DL"), localTrialRows("UL"), struct());
assert(~logical(rootMissingReason.Status.KpiConsistencyOk), ...
    "A not-applicable KPI without an applicability reason must fail closed.");

ok = true;
end

function T = localTrialRows(direction)
T = table(string(direction), 0, 1, 1, "QPSK", 1, false, ...
    'VariableNames', {'Direction','Slot','Layers','Rank','Modulation','MCS', ...
    'IsWarmupFrame'});
end
