function ok = testLLS700MHzTruthSNRResponse()
%TESTLLS700MHZTRUTHSNRRESPONSE Guard fixed truth LLS SNR response on the 700 MHz preset.

setup6GRSimToolkit("Verbose", false);

scenarioPath = fullfile(pwd, "simulator", "configs", "scenarios", "lls_700mhz_20mhz_2x2_rank2_beam_truth.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tempdir, "lls_700mhz_truth_snr_probe"));
assert(string(cfg.phy.pdsch.executionProfile) == "phy_calibration" && ...
    string(cfg.phy.pusch.executionProfile) == "phy_calibration", ...
    "The truth probe execution profile must come from YAML authority.");
expectedProfile = sixgr.link.resolveMCSProfile(scfg.get("modulation.mcs_table"), scfg.get("modulation.dl_mcs_index"));
expectedMCS = double(scfg.get("modulation.dl_mcs_index"));
assert(logical(expectedProfile.Valid), ...
    "700 MHz truth probe must resolve a valid NR MCS profile.");

lowProbeSNR_dB = -10;
highProbeSNR_dB = 40;
dlLow = sixgr.link.runDLPDSCHThroughput(cfg, "NumFrames", 4, "SNR_dB", lowProbeSNR_dB);
dlHigh = sixgr.link.runDLPDSCHThroughput(cfg, "NumFrames", 4, "SNR_dB", highProbeSNR_dB);
ulLow = sixgr.link.runULPUSCHThroughput(cfg, "NumFrames", 4, "SNR_dB", lowProbeSNR_dB);
ulHigh = sixgr.link.runULPUSCHThroughput(cfg, "NumFrames", 4, "SNR_dB", highProbeSNR_dB);

fprintf(["700 MHz truth SNR response: DL BLER %.4f -> %.4f, " + ...
    "SINR %.3f -> %.3f dB; UL BLER %.4f -> %.4f, " + ...
    "SINR %.3f -> %.3f dB.\n"], ...
    dlLow.BLER, dlHigh.BLER, ...
    mean(dlLow.TrialTable.MeasuredSINR_dB, "omitnan"), ...
    mean(dlHigh.TrialTable.MeasuredSINR_dB, "omitnan"), ...
    ulLow.BLER, ulHigh.BLER, ...
    mean(ulLow.TrialTable.MeasuredSINR_dB, "omitnan"), ...
    mean(ulHigh.TrialTable.MeasuredSINR_dB, "omitnan"));

assert(all(dlHigh.TrialTable.Layers == 2) && all(ulHigh.TrialTable.Layers == 2), ...
    "High-SNR fixed truth probe must preserve the configured 2-layer operating point.");
assert(all(dlHigh.TrialTable.MCS == expectedMCS) && all(ulHigh.TrialTable.MCS == expectedMCS), ...
    "High-SNR fixed truth probe must preserve the configured MCS.");
assert(all(string(dlHigh.TrialTable.Modulation) == string(expectedProfile.Modulation)) && ...
    all(string(ulHigh.TrialTable.Modulation) == string(expectedProfile.Modulation)), ...
    "High-SNR fixed truth probe must derive modulation from the resolved NR MCS profile.");
assert(all(abs(double(dlHigh.TrialTable.TargetCodeRate) - double(expectedProfile.TargetCodeRate)) < 1e-9) && ...
    all(abs(double(ulHigh.TrialTable.TargetCodeRate) - double(expectedProfile.TargetCodeRate)) < 1e-9), ...
    "High-SNR fixed truth probe must derive code rate from the resolved NR MCS profile.");
assert(dlHigh.BLER < dlLow.BLER && ulHigh.BLER < ulLow.BLER, ...
    "High-SNR fixed truth probe must improve BLER relative to the low-SNR point.");
assert(dlHigh.BLER == 0 && ulHigh.BLER == 0, ...
    "The explicit 40 dB fixed truth probe must decode cleanly on both links.");
assert(all(isfinite(dlHigh.TrialTable.RankIndicator)) && all(isfinite(ulHigh.TrialTable.RankIndicator)), ...
    "High-SNR fixed truth probe must still emit CSI-recommended RI values.");
assert(all(isfinite(dlHigh.TrialTable.BeamHit)) && mean(dlHigh.TrialTable.BeamHit, "omitnan") > 0, ...
    "DL beam diagnostics must not collapse a rank-2 PMI run into a zero-hit single-beam proxy.");
assert(all(isnan(ulHigh.TrialTable.BeamHit)) && all(isnan(ulHigh.TrialTable.BestBeamIndex)) && ...
    all(string(ulHigh.TrialTable.BeamScoreSource) == ...
    "not_evaluated_pusch_dmrs_effective_layer_channel_cannot_rescore_tpmi"), ...
    ["UL PUSCH-DMRS effective-layer evidence must not be used to score " + ...
    "counterfactual TPMIs or manufacture a best-beam hit."]);
assert(all(isfinite(ulHigh.TrialTable.AppliedPrecoderPMI)) && ...
    all(string(ulHigh.TrialTable.PrecodingMode) == "ul_codebook_tpmi") && ...
    all(string(ulHigh.TrialTable.PMISource) == ...
    "ul_runtime_applied_codebook_tpmi_from_pusch_waveform"), ...
    "UL trials must retain the waveform-applied TPMI separately from unavailable beam recommendation evidence.");
assert(all(isfinite(dlHigh.TrialTable.NMSE_dB)) && all(isfinite(ulHigh.TrialTable.NMSE_dB)), ...
    "DL/UL truth trial tables must populate NMSE_dB.");
assert(all(isfinite(dlHigh.TrialTable.DetectionMetric)) && all(isfinite(ulHigh.TrialTable.DetectionMetric)), ...
    "DL/UL truth trial tables must populate DetectionMetric.");
assert(mean(dlHigh.TrialTable.MeasuredSINR_dB, "omitnan") > mean(dlLow.TrialTable.MeasuredSINR_dB, "omitnan") + 10, ...
    "DL measured SINR must increase materially with SNR.");
assert(mean(ulHigh.TrialTable.MeasuredSINR_dB, "omitnan") > mean(ulLow.TrialTable.MeasuredSINR_dB, "omitnan") + 10, ...
    "UL measured SINR must increase materially with SNR.");
assert(mean(dlHigh.TrialTable.NoiseVariance, "omitnan") < mean(dlLow.TrialTable.NoiseVariance, "omitnan"), ...
    "DL noise variance must decrease as configured SNR increases.");
assert(mean(ulHigh.TrialTable.NoiseVariance, "omitnan") < mean(ulLow.TrialTable.NoiseVariance, "omitnan"), ...
    "UL noise variance must decrease as configured SNR increases.");

ok = true;
end
