function ok=test5MHzRank2SharedAWGNSweepIsolation(scenarioPath)
%TEST5MHZRANK2SHAREDAWGNSWEEPISOLATION Every SNR point owns a fresh PHY.

setup6GRSimToolkit('Verbose',false);
if nargin<1
    scenarioPath=fullfile('simulator','configs','scenarios', ...
        'lls_tdd_5mhz_rank2_shared_awgn_snr_sweep.yaml');
end
parent=sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
assert(string(parent.get('scenario.runner_profile'))=="generic_sweep", ...
    'test:SharedAWGNSweepNotIsolated', ...
    'The 5 MHz AWGN sweep must use independently constructed child runs.');
assert(string(parent.get('scenario.sweep.base_profile'))=="waveform_bundle");
assert(~logical(parent.get('canonical_control.launch.sweep_enabled')) && ...
    ~logical(parent.get('sweeps_and_matrix.snr_sweep.enabled')), ...
    'test:NestedSNRSweepForbidden', ...
    'A child physical runtime must contain exactly one fixed SNR point.');

overrides=parent.get('scenario.sweep.overrides');
expected=[-30 -20 -10 0 10 20 30 40];
assert(numel(overrides)==numel(expected));
scenarioIDs=strings(numel(expected),1);
noiseSeeds=zeros(numel(expected),1);
for pointIndex=1:numel(expected)
    authority=overrides(pointIndex).config;
    resolved=sixgr.util.mergeStruct(parent.toStruct(),authority);
    resolved=sixgr.lls6g.config.normalizeScenarioAliases(resolved, ...
        'SourceFiles',parent.SourceFiles,'ConfigPath',parent.ConfigPath, ...
        'Authority',authority);
    resolved.scenario.runner_profile='waveform_bundle';
    sixgr.lls6g.config.validateScenarioConfig(resolved, ...
        'Kind','scenario','AllowPartial',false, ...
        'Context',parent.ConfigPath+"::"+string(overrides(pointIndex).label));
    child=sixgr.lls6g.config.ScenarioConfig(resolved, ...
        'SourceFiles',parent.SourceFiles,'ConfigPath',parent.ConfigPath, ...
        'ConfigHash',sixgr.lls6g.config.hashResolvedScenario(resolved), ...
        'Kind','scenario');
    cfg=sixgr.lls6g.buildInternalConfig(child,tempname);
    configured=double(child.get('simulation.snr_db'));
    assert(configured==expected(pointIndex) && ...
        double(cfg.channel.snr_dB)==expected(pointIndex), ...
        'test:SharedAWGNSweepPhysicalSNRDrift', ...
        'Point %s resolved to YAML/PHY SNR %.12g/%.12g dB, expected %.12g dB.', ...
        string(overrides(pointIndex).label),configured, ...
        double(cfg.channel.snr_dB),expected(pointIndex));
    assert(~cfg.run.snrSweepEnabled && ...
        isequal(double(cfg.run.snrSweepOffsets_dB(:).'),0), ...
        'test:SharedAWGNNestedRuntimeSweep', ...
        'Point %s still contains a live multi-point runtime sweep.', ...
        string(overrides(pointIndex).label));
    carrier=sixgr.phy.grid.makeCarrier(cfg);
    ofdm=nrOFDMInfo(carrier);
    % Match the normal coupled owner exactly. An artificial per-test epoch
    % would make seeds different even if production accidentally reused the
    % same physical SNR/noise identity for every independently launched child.
    owner=sixgr.truth.SharedWaveformPhysicalRuntime( ...
        ofdm.SampleRate,0,cfg.rf.configurationEpoch);
    owner.addTransmitter('silent',cfg,'DL',4,false);
    owner.addReceiver('ue',cfg,'DL',4,false);
    % Independent scoring of actual generated noise, not just its ledger.
    % Four OFDM slots provide many independent samples without executing
    % access/scheduling. The configured variance is never a receiver input.
    sampleCount=4*sum(double(ofdm.SymbolLengths));
    event=sixgr.phy.waveform.WaveformEventRuntime(ofdm.SampleRate,0,@owner.process,owner);
    owner.attach(event,'double');
    event.commitTransmissionsThrough('silent',sampleCount);
    for plane=["silent:tx","ue:pre_rf","ue:post_rf"]
        event.observe(plane,plane,0,sampleCount);
    end
    event.advanceUntilEvent(floor(sampleCount/2));
    capture=event.advanceUntilEvent(sampleCount);
    % Exercise the same segmented-observation adapter used by shared PBCH,
    % rather than testing only a direct physical-owner replay structure.
    [~,preObservation,~,replay]=sixgr.truth.sharedObservationEvidence(capture.Completed);
    assert(isfield(replay,'AppliedAWGNSNR_dB') && ...
        abs(replay.AppliedAWGNSNR_dB-expected(pointIndex))<1e-10, ...
        'test:MissingPhysicalAppliedSNR', ...
        'Physical receiver execution must retain the SNR of the variance actually injected.');
    assert(replay.AppliedAWGNSNRSource=="executed_sample_noise_variance_and_occupied_re_energy" && ...
        replay.AppliedAWGNSNRValueRole=="applied_noise_reference_not_measured_receiver_sinr");
    pbchRow=sixgr.truth.bindPBCHReceiverSINREvidence(struct( ...
        'ChannelEstimateAvailable',false,'EqualizationAvailable',false), ...
        struct('RuntimeChannelReplay',replay),struct());
    assert(pbchRow.AppliedAWGNSNR_dB==replay.AppliedAWGNSNR_dB && ...
        pbchRow.AppliedAWGNSNRSource==replay.AppliedAWGNSNRSource && ...
        isnan(pbchRow.MeasuredSINR_dB), ...
        'Applied noise provenance must reach PBCH without inventing a receiver measurement.');
    referenceEnergy=sixgr.link.resolveAWGNReferenceEnergy(cfg);
    calibration=sixgr.phy.waveform.calibrateOFDMNoiseTransform(carrier);
    expectedGridVariance=referenceEnergy*10^(-expected(pointIndex)/10);
    expectedSampleVariance=expectedGridVariance/ ...
        double(calibration.SampleToGridNoiseVarianceGain);
    tolerance=1e-12*max(1,expectedGridVariance);
    assert(double(replay.RequestedAWGNReferenceSNR_dB)==expected(pointIndex) && ...
        abs(double(replay.GridNoiseVariance)-expectedGridVariance)<=tolerance && ...
        abs(double(replay.InjectedNoiseVariance)-expectedSampleVariance)<= ...
            1e-12*max(1,expectedSampleVariance), ...
        'test:SharedAWGNSweepNoiseCalibrationDrift', ...
        ['Point %s did not recalculate occupied-RE and sample-domain ' ...
         'noise from its own fixed SNR.'],string(overrides(pointIndex).label));
    samples=preObservation.readComplete();
    measuredSampleVariance=mean(abs(double(samples(:))).^2);
    grid=nrOFDMDemodulate(carrier,samples,'Nfft',ofdm.Nfft);
    measuredGridVariance=mean(abs(double(grid(:))).^2);
    sampleError_dB=10*log10(measuredSampleVariance/expectedSampleVariance);
    gridError_dB=10*log10(measuredGridVariance/expectedGridVariance);
    assert(isfinite(sampleError_dB) && abs(sampleError_dB)<0.3 && ...
        isfinite(gridError_dB) && abs(gridError_dB)<0.3, ...
        'test:SharedAWGNSweepActualNoiseDrift', ...
        ['Point %s actual generated noise differs from independent ' ...
         'sample/grid expectations by %.6g/%.6g dB.'], ...
        string(overrides(pointIndex).label),sampleError_dB,gridError_dB);
    % Compare actual main-runtime samples with the occupied-RE primitive
    % used by fixed-link/HARQ and the FRC adapter. Independent seeds prevent
    % agreement from merely replaying the same random vector. Do not force
    % realized noise to match its nominal variance by renormalizing it.
    before=rng;
    primitive=sixgr.phy.waveform.addOccupiedREAWGN( ...
        complex(zeros(size(samples))),carrier,expected(pointIndex), ...
        'SignalEnergyPerOccupiedRE',referenceEnergy,'Seed',382120+pointIndex);
    assert(isequal(before,rng),'The comparison must not change runtime RNG state.');
    primitiveGrid=nrOFDMDemodulate(carrier,primitive,'Nfft',ofdm.Nfft);
    primitiveVariance=mean(abs(double(primitiveGrid(:))).^2);
    crossPathError_dB=10*log10(measuredGridVariance/primitiveVariance);
    assert(abs(10*log10(primitiveVariance/expectedGridVariance))<0.3 && ...
        abs(crossPathError_dB)<0.3, ...
        'test:SharedAWGNCrossPathNoiseDrift', ...
        'Main runtime versus occupied-RE primitive differs by %.6g dB at %g dB.', ...
        crossPathError_dB,expected(pointIndex));
    % Four receive dimensions must have independent circular noise. A
    % scalar noise vector copied across antennas can pass mean-power tests
    % while invalidating rank-two post-equalization SINR and decoding.
    maxSpatialCorrelation=0;
    for noise={grid,primitiveGrid}
        branches=reshape(double(noise{1}),[],size(samples,2));
        branches=branches-mean(branches,1);
        covariance=(branches'*branches)/size(branches,1);
        pseudocovariance=(branches.'*branches)/size(branches,1);
        powers=real(diag(covariance));
        assert(all(abs(10*log10(powers/expectedGridVariance))<0.3));
        normalization=sqrt(powers*powers.');
        correlation=covariance./normalization;
        correlation(1:size(correlation,1)+1:end)=0;
        % Family-wise alpha=0.001 across all points, paths and entries.
        % For independent circular complex Gaussian samples, squared
        % sample circularity has Beta(1,(N-2)/2) distribution. This tail
        % also conservatively bounds pairwise complex correlation. Use
        % the actual number of RE observations, not a fixed threshold.
        comparisons=numel(expected)*2*2*size(branches,2)^2;
        alpha=0.001/comparisons;
        limit=sqrt(-expm1(2*log(alpha)/(size(branches,1)-2)));
        observed=max([abs(correlation(:));abs(pseudocovariance(:)./normalization(:))]);
        maxSpatialCorrelation=max(maxSpatialCorrelation,observed);
        assert(observed<limit, ...
            'test:SharedAWGNSpatialNoiseCorrelation', ...
            'AWGN correlation/circularity %.6g exceeds family-wise bound %.6g (N=%d).', ...
            observed,limit,size(branches,1));
    end
    fprintf(['SWEEP_ACTUAL_NOISE snr_db=%g sample_error_db=%.6g ' ...
        'grid_error_db=%.6g cross_path_error_db=%.6g max_spatial_correlation=%.6g ' ...
        'spatial_limit=%.6g spatial_noise_pass=1\n'], ...
        expected(pointIndex),sampleError_dB,gridError_dB,crossPathError_dB,maxSpatialCorrelation,limit);
    noiseSeeds(pointIndex)=double(replay.NoiseStreamSeed);
    scenarioIDs(pointIndex)=string(child.ScenarioID);
end
assert(numel(unique(scenarioIDs))==numel(expected), ...
    'test:SharedAWGNSweepIdentityCollision', ...
    'Every physical SNR point must have a unique scenario identity.');
assert(numel(unique(noiseSeeds))==numel(expected), ...
    'test:SharedAWGNSweepNoiseStreamReuse', ...
    'Every isolated SNR point must construct its own physical noise stream.');
fprintf('5MHZ_SHARED_AWGN_SWEEP_ISOLATION_PASS points=%d snr_db=%s\n', ...
    numel(expected),mat2str(expected));
ok=true;
end
