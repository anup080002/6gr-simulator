function ok = testPDSCHDMRSSequenceIndependent()
%TESTPDSCHDMRSSEQUENCEINDEPENDENT Compare production to independent Gold RS.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
cases = [ ...
    localCase("SEQ-1", "A", 1, 1, 0, 12, 2, 1, ...
        1, [0 1], 0:3, 0, 0, 0, false); ...
    localCase("SEQ-2", "B", 2, 1, 4, 8, 2, 2, ...
        2, [0 1], 2:7, 321, 1, 7, false); ...
    localCase("SEQ-3", "A", 1, 2, 0, 12, 2, 1, ...
        1, [0 1], 0:4, 65535, 1, 19, false); ...
    localCase("SEQ-4", "A", 2, 2, 0, 14, 2, 1, ...
        3, 0:7, 0:3, 42, 0, 0, false); ...
    localCase("SEQ-5", "A", 2, 1, 0, 14, 2, 3, ...
        3, [0:5 12 13], 0:3, 42, 0, 0, true); ...
    localCase("SEQ-6", "B", 1, 1, 1, 13, 2, 2, ...
        2, [0:3 8], [0 2 3], 42, 0, 0, true)];

comparisonCount = 0;
for i = 1:numel(cases)
    c = cases(i);
    carrier = nrCarrierConfig;
    carrier.NSizeGrid = max(c.PRBSet) + 1;
    carrier.SubcarrierSpacing = 30;
    carrier.NCellID = mod(c.NIDNSCID, 1008);
    carrier.NSlot = c.SlotNumber;
    pdsch = nrPDSCHConfig;
    pdsch.PRBSet = c.PRBSet;
    pdsch.SymbolAllocation = [c.StartSymbol c.Duration];
    pdsch.MappingType = char(c.MappingType);
    pdsch.NumLayers = numel(c.PortSet);
    pdsch.Modulation = "QPSK";
    pdsch.DMRS.DMRSConfigurationType = c.ConfigurationType;
    pdsch.DMRS.DMRSLength = c.DMRSLength;
    pdsch.DMRS.DMRSAdditionalPosition = c.AdditionalPosition;
    pdsch.DMRS.DMRSTypeAPosition = c.TypeAPosition;
    pdsch.DMRS.DMRSPortSet = c.PortSet;
    pdsch.DMRS.NIDNSCID = c.NIDNSCID;
    pdsch.DMRS.NSCID = c.NSCID;
    pdsch.DMRS.DMRSEnhancedR18 = c.Enhanced;

    dmrsSymbols = sixgr.pdsch.PDSCHDMRSValidator. ...
        resolveSymbolPositions(c.MappingType, c.DMRSLength, ...
        c.StartSymbol, c.Duration, c.TypeAPosition, ...
        c.AdditionalPosition);
    request = struct( ...
        "DMRSConfigurationType", c.ConfigurationType, ...
        "DMRSLength", c.DMRSLength, ...
        "DMRSPortSet", c.PortSet, ...
        "DMRSSymbols", dmrsSymbols, ...
        "PRBSet", c.PRBSet, ...
        "NIDNSCID", c.NIDNSCID, "NSCID", c.NSCID, ...
        "SlotNumber", c.SlotNumber, ...
        "SymbolsPerSlot", carrier.SymbolsPerSlot);
    oracle = sixgr.pdsch.oracle.DMRSSequenceSpec.generate(request);
    [indices, actual] = sixgr.phy.refsig.dmrsPDSCH( ...
        carrier, pdsch, "IndexBase", "0based");
    actual = localShape(actual, numel(c.PortSet));
    assert(isequal(size(actual), size(oracle.Sequence)), ...
        "DM-RS sequence dimensions mismatch for %s.", c.CaseID);
    maxError = max(abs(double(actual(:)) - oracle.Sequence(:)));
    assert(maxError <= 1e-12, ...
        "Independent DM-RS sequence mismatch for %s: %.3g.", ...
        c.CaseID, maxError);
    assert(size(indices, 1) == size(oracle.Sequence, 1), ...
        "DM-RS index/sequence length mismatch for %s.", c.CaseID);
    assert(all(isfinite(real(actual)), "all") && ...
        all(isfinite(imag(actual)), "all"), ...
        "Production DM-RS sequence is nonfinite for %s.", c.CaseID);
    comparisonCount = comparisonCount + numel(actual);
end
assert(comparisonCount > 0, ...
    "Independent DM-RS sequence test compared no samples.");
ok = true;
end

function c = localCase(id, mapping, configType, dmrsLength, start, ...
        duration, typeAPosition, additional, numCDM, ports, prbs, ...
        nid, nscid, slot, enhanced)
c = struct( ...
    "CaseID", string(id), "MappingType", string(mapping), ...
    "ConfigurationType", configType, "DMRSLength", dmrsLength, ...
    "StartSymbol", start, "Duration", duration, ...
    "TypeAPosition", typeAPosition, ...
    "AdditionalPosition", additional, ...
    "NumCDMGroupsWithoutData", numCDM, ...
    "PortSet", ports, "PRBSet", prbs, ...
    "NIDNSCID", nid, "NSCID", nscid, "SlotNumber", slot, ...
    "Enhanced", logical(enhanced));
end

function value = localShape(value, numPorts)
if numPorts > 1 && isvector(value)
    assert(mod(numel(value), numPorts) == 0, ...
        "Production DM-RS vector cannot be separated by port.");
    value = reshape(value, [], numPorts);
end
end
