function ok = testPDSCHTransmitterExplicitPipeline()
%TESTPDSCHTRANSMITTEREXPLICITPIPELINE Prove every strict TX stage executes.

setup6GRSimToolkit("Verbose", false);
fixture = StrictPDSCHChainFixture.create(2, "UsePTRS", true);
tx = sixgr.pdsch.PDSCHTransmitter( ...
    fixture.TransportBlocks, fixture.Assignment, fixture.ResourcePlan, ...
    fixture.Carrier, fixture.ReferenceConfig, ...
    "PrecoderBundle", fixture.PrecoderBundle);

expectedStages = ["assignment","resource_plan","dlsch_coding", ...
    "scrambling","modulation","layer_mapping","precoding", ...
    "dmrs_generation","ptrs_generation","reference_mapping", ...
    "resource_grid","ofdm_modulation"];
assert(isequal(tx.StageTrace.Stage, expectedStages.'), ...
    "Strict transmitter stage trace is incomplete or reordered.");
assert(all(tx.StageTrace.Status == "PASS") ...
    && all(tx.StageTrace.MaterializedElementCount > 0), ...
    "Every strict transmitter stage must materialize real output.");
assert(numel(tx.RateMatchedBits) == 1 ...
    && numel(tx.RateMatchedBits{1}) == tx.CodingPlans{1}.RateMatchedBitCount, ...
    "DLSCH encoder output does not match immutable G.");
assert(~isequal(tx.RateMatchedBits{1}, tx.ScrambledBits{1}), ...
    "PDSCH scrambling stage did not transform the encoded bits.");
assert(size(tx.LayerSymbols,2) == 2 ...
    && size(tx.DataPortSymbols,1) == 2, ...
    "Layer mapping and physical-port precoding were not materialized.");
assert(height(tx.DataPrecoderTrace) == fixture.ResourcePlan.ExactDataRECount ...
    && all(tx.DataPrecoderTrace.AppliedMatrixDigest ...
    == tx.DataPrecoderTrace.ResolvedMatrixDigest), ...
    "Exact data-RE precoder application evidence is incomplete.");
assert(nnz(tx.Grid) > 0 && any(abs(tx.Waveform(:)) > 0), ...
    "Grid mapping or OFDM modulation produced no signal.");

assert(tx.ReferenceSignals.DMRSIndexMismatchCount == 0 ...
    && tx.ReferenceSignals.PTRSIndexMismatchCount == 0 ...
    && tx.ReferenceSignals.DMRSSequenceNMSE <= 1e-24 ...
    && tx.ReferenceSignals.PTRSSequenceNMSE <= 1e-24, ...
    "Transmitter reference generation did not pass independent checks.");

withoutPTRS = StrictPDSCHChainFixture.create(1, "UsePTRS", false);
txWithoutPTRS = sixgr.pdsch.PDSCHTransmitter( ...
    withoutPTRS.TransportBlocks, withoutPTRS.Assignment, ...
    withoutPTRS.ResourcePlan, withoutPTRS.Carrier, ...
    withoutPTRS.ReferenceConfig, ...
    "PrecoderBundle", withoutPTRS.PrecoderBundle);
ptrsStage = txWithoutPTRS.StageTrace( ...
    txWithoutPTRS.StageTrace.Stage == "ptrs_generation", :);
assert(height(ptrsStage) == 1 ...
    && ptrsStage.Status == "PASS" ...
    && ptrsStage.MaterializedElementCount == 0 ...
    && isempty(txWithoutPTRS.PTRSPortSymbols) ...
    && isempty(txWithoutPTRS.PTRSIndices), ...
    "Disabled PT-RS must report exactly zero materialized elements.");
fprintf("PDSCH strict TX pipeline: 12/12 explicit stages pass\n");
ok = true;
end
