function ok = testH4100EightPointSweepConfig()
%TESTH4100EIGHTPOINTSWEEPCONFIG Lock the complete H4 sweep contract.

setup6GRSimToolkit("Verbose", false);
scenarioPath = fullfile("simulator", "configs", "scenarios", ...
    "h4_100_cdlc100_connected_impaired_snr_sweep.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
raw = scfg.toStruct();

assert(string(scfg.get("scenario.runner_profile")) == "generic_sweep");
assert(string(scfg.get("scenario.sweep.base_profile")) == "waveform_bundle");
assert(string(scfg.get("scenario.sweep.execution_error_policy")) == ...
    "retain_failure_and_continue");
assert(string(scfg.get("sweeps_and_matrix.snr_sweep.state_policy")) == ...
    "independent_link_state_per_point");
assert(string(scfg.get("sweeps_and_matrix.snr_sweep.initial_access_state_policy")) == ...
    "independent_per_point");
assert(~logical(scfg.get("output.profiler_enabled")), ...
    "The production sweep must not retain the unbounded diagnostic call profiler.");

overrides = scfg.get("scenario.sweep.overrides");
assert(numel(overrides) == 8, "The H4 campaign must contain exactly eight points.");
expectedSNR = [40 30 20 10 0 -10 -20 -30];
observedSNR = arrayfun(@(x) double(x.config.simulation.snr_db), overrides);
assert(isequal(observedSNR(:).', expectedSNR), ...
    "Configured-SNR order must be 40,30,20,10,0,-10,-20,-30 dB.");
assert(all(arrayfun(@(x) double(x.config.simulation.random_seed), overrides) == 20260927), ...
    "All points must use the frozen paired channel/noise seed.");

for pointIndex = 1:numel(overrides)
    child = sixgr.util.mergeStruct(raw, overrides(pointIndex).config);
    child.scenario.runner_profile = "waveform_bundle";
    child = sixgr.lls6g.config.normalizeScenarioAliases(child, ...
        "SourceFiles", scfg.SourceFiles, "ConfigPath", scfg.ConfigPath, ...
        "Authority", overrides(pointIndex).config);
    sixgr.lls6g.config.validateScenarioConfig(child, "Kind", "scenario", ...
        "AllowPartial", false, "Context", scenarioPath + "::test_point");
    childCfg = sixgr.lls6g.config.ScenarioConfig(child, ...
        "SourceFiles", scfg.SourceFiles, "ConfigPath", scfg.ConfigPath, ...
        "ConfigHash", sixgr.lls6g.config.hashResolvedScenario(child), ...
        "Kind", "scenario");
    cfg = sixgr.lls6g.buildInternalConfig(childCfg, ...
        fullfile(tempdir, "h4_100_eight_point_sweep", string(pointIndex)));

    assert(double(cfg.phy.nTxAnt) == 64 && double(cfg.phy.nRxAnt) == 4);
    assert(double(cfg.phy.pusch.numAntennaPorts) == 4 && ...
        double(cfg.phy.srs.nPorts) == 4);
    assert(double(cfg.phy.pdsch.maxRankDefault) == 4 && ...
        double(cfg.phy.pusch.maxRankDefault) == 4);
    assert(double(cfg.phy.csirs.nPorts) == 4 && ...
        double(cfg.phy.csirs.numResources) == 8);
    assert(~logical(cfg.run.controlGating.srsRequired) && ...
        logical(cfg.run.controlGating.trsRequired) && ...
        double(cfg.run.controlGating.trsMaxAgeSlots) == 20 && ...
        double(cfg.phy.trs.period_slots) == 20, ...
        ["H4 DL admission must be CSI-RS/report-owned rather than globally " ...
         "SRS-gated, while TRS freshness covers its complete 20-slot cadence."]);
    assert(logical(cfg.phy.impairments.cfoEnabled) && ...
        logical(cfg.phy.impairments.phaseNoiseEnabled) && ...
        logical(cfg.phy.impairments.iqImbalanceEnabled) && ...
        logical(cfg.phy.impairments.paNonlinearityEnabled) && ...
        logical(cfg.phy.impairments.adcQuantizationEnabled) && ...
        logical(cfg.phy.impairments.dacQuantizationEnabled) && ...
        logical(cfg.phy.impairments.timingOffsetEnabled), ...
        "Every H4 sweep child must retain the frozen RF-impairment treatment.");
    assert(double(cfg.channel.snr_dB) == expectedSNR(pointIndex), ...
        "The physical child receiver must receive its configured SNR.");
    assert(~logical(cfg.mac.scheduler.fastNREApprox), ...
        "H4 sweep children must use exact grant/TBS accounting.");
    assert(string(cfg.outputs.plannedAllocationEncoding) == ...
        "exact_periodic_templates", ...
        ["The 200-slot H4 child must retain exact RE coordinates in the " ...
         "bounded periodic-template representation."]);
end

ok = true;
end
