function ok = testPDSCHReceiverNoSignal()
%TESTPDSCHRECEIVERNOSIGNAL All-zero waveform must fail closed.

setup6GRSimToolkit("Verbose", false);
fixture = StrictPDSCHChainFixture.create(1);
tx = sixgr.pdsch.PDSCHTransmitter( ...
    fixture.TransportBlocks,fixture.Assignment,fixture.ResourcePlan, ...
    fixture.Carrier,fixture.ReferenceConfig, ...
    "PrecoderBundle",fixture.PrecoderBundle);
localAssertIdentifier(@() sixgr.pdsch.PDSCHReceiver( ...
    zeros(size(tx.Waveform)),fixture.Assignment,fixture.ResourcePlan, ...
    fixture.Carrier,fixture.ReferenceConfig,fixture.ReceiverConfig, ...
    "CodingPlans",tx.CodingPlans, ...
    "PrecoderBundle",fixture.PrecoderBundle), ...
    "sixgr:pdsch:PDSCHReceiver:NoReceivedSignal");
fprintf("PDSCH strict RX no-signal: typed fail-closed pass\n");
ok = true;
end

function localAssertIdentifier(fn,identifier)
try
    fn();
catch cause
    assert(string(cause.identifier) == string(identifier), ...
        "Observed %s, expected %s.",cause.identifier,identifier);
    return;
end
error("sixgr:test:ExpectedErrorNotThrown", ...
    "Expected error %s was not thrown.",identifier);
end
