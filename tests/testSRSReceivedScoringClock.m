function ok=testSRSReceivedScoringClock()
% Native four-port SRS with declared, executed sample-domain RX clock steps.
% This component is not a full RF, fading, access or statistical campaign.
setup6GRSimToolkit('Verbose',false);
source=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/scenarios/lls_tdd_5mhz_four_port_shared_awgn_12db.yaml');
cfg=sixgr.lls6g.buildInternalConfig(source,tempname);
cfg=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,5,1);
cfg.phy.srs.runtimeChannelEstimator='nr_channel_estimate';
args={'SlotIndex',5,'TrialIndex',1,'SNR_dB',40,'TimingAdvanceSamples',0};
pending=sixgr.link.runSRSChannelEstimation(cfg,args{:},'PrepareOnly',true);
p=pending.PreparedTransmission; fs=p.SampleRateHz;
assert(p.StartSample==p.ReceiveStartSample && p.NumReceiveAntennas==4);
array=sixgr.rf.AntennaArrayFactory.build(p.ReceiverConfig,'ue', ...
    'signal','srs','numPorts',size(p.Tx.Waveform,2));
x=p.Tx.Waveform*array.PortToElementMatrix.';
link=x*diag([1,0.8*exp(.3i),0.7*exp(-.4i),.9]);
desired=[link;complex(zeros(64,4))];
energy=sixgr.phy.waveform.measureReceivedOccupiedREEnergy( ...
    p.Tx.Carrier,link,p.Tx.SRSIndices,'SignalFamily','SRS');
prior=rng; cleanup=onCleanup(@()rng(prior)); %#ok<NASGU>
rng(2401432,'twister');
[pre,~]=sixgr.phy.waveform.addOccupiedREAWGN( ...
    desired,p.Tx.Carrier,40,'SignalEnergyPerOccupiedRE',energy);
for pair=[0 0;1 400;16 -800].'
    delay=pair(1); hz=pair(2);
    n=p.ReceiveStartSample+(0:size(pre,1)-1).';
    post=[complex(zeros(delay,4));pre(1:end-delay,:)];
    post=post.*exp(2i*pi*hz/fs*n);
    endpoint=struct('InjectedTimingOffset_samples',delay,'CFOApplied',hz~=0, ...
        'InjectedCFO_Hz',hz,'RFEndpoint',"rx", ...
        'RFStageOrder',"rx_timing>rx_lo_cfo");
    execution=struct('ReceiverID',"declared_gnb",'TransmitterID',"declared_ue", ...
        'ReceiveStreamExecutionSegments',{{struct('StartSample',p.ReceiveStartSample, ...
        'EndSampleExclusive',p.ReceiveStartSample+size(post,1), ...
        'Execution',struct('RX',struct('ID',"declared_gnb",'Replay',endpoint)))}});
    evidence=struct('Source',"actual_executed_link_contribution", ...
        'ReceiverID',execution.ReceiverID,'TransmitterID',execution.TransmitterID, ...
        'ReceiverEstimatorInput',false,'AdditionalChannelExecutions',0, ...
        'AdditionalRFExecutions',0,'ReceiverClockExecution',execution);
    replay=execution;
    replay.SampleNoiseVariance=NaN;
    replay.SampleNoiseVarianceDomain="unavailable_requires_received_reference_estimation";
    replay.NoiseOperatingMode="standalone_awgn_snr_argument";
    replay.ApproximationMode="none";
    input=struct('Prepared',p,'Observation',buffer(post,p.ReceiveStartSample,fs), ...
        'PhysicalMeasurementObservation',buffer(pre,p.ReceiveStartSample,fs), ...
        'TransmitterObservation',buffer(x,p.StartSample,fs),'Replay',replay, ...
        'DesiredReferenceObservation',buffer(desired,p.ReceiveStartSample,fs), ...
        'DesiredReferenceEvidence',evidence, ...
        'ChannelState',struct('Source',"declared_four_branch_clock_component"));
    before=rng;
    [out,capture]=sixgr.link.runSRSChannelEstimation(cfg,args{:},'ReceivedContext',input);
    assert(isequal(before,rng));
    t=capture.Rx.Timing; first=t.AppliedTimingCorrectionSamples;
    indices=first+(1:t.DemodulatedSampleCount);
    assert(first>=delay && ~t.OracleTimingUsed);
    % Independent exact applied RX operator, not the production scoring helper.
    expectedWave=desired(indices-delay,:).*exp(2i*pi*hz/fs*n(indices));
    grid=sixgr.phy.waveform.ofdmDemodulate(p.Tx.Carrier,expectedWave);
    reference=nrChannelEstimate(p.Tx.Carrier,grid, ...
        p.Tx.SRSIndices,p.Tx.SRSSymbols,'CDMLengths',[4 1]);
    expected=sixgr.phy.srs.pilotChannelPhaseEquivalentNMSE( ...
        capture.Rx.Hest,reference,p.Tx.SRSIndices);
    assert(abs(out.NMSE_dB-expected.dB)<1e-9, ...
        'test:SRSReceiverClockMismatch','SRS scoring must use the executed RX-only clock.');
    e=out.ChannelNMSEReferenceEvidence;
    assert(out.Ok && e.ReceiverTimingIncluded && e.ReceiverCFOIncluded && ...
        e.RecordedReceiverTimingOffset_samples==delay && e.ExecutedReceiverCFO_Hz==hz && ...
        ~e.ReceiverEstimatorInput && ~e.ComparisonGainFitted);
    row=table(out.NMSE_dB,out.TrueChannelNMSE_dB,string(out.NMSEReferenceSource), ...
        'VariableNames',{'NMSE_dB','TrueChannelNMSE_dB','NMSEReferenceSource'});
    row=sixgr.truth.bindSharedSRSNMSEEvidence(row,out);
    assert(row.ChannelNMSEGainOrPhaseFitted==out.ChannelNMSEScoring.GainOrPhaseFitted && ...
        row.ChannelNMSEPhaseAligned==out.ChannelNMSEScoring.PhaseAligned && ...
        ~row.ChannelNMSEGainFitted, ...
        'Selected phase-equivalent NMSE must disclose phase alignment, without a gain fit.');
    assert(row.ChannelNMSEReceiverTimingIncluded && row.ChannelNMSEReceiverCFOIncluded && ...
        row.ChannelNMSERecordedReceiverTimingOffset_samples==delay && ...
        row.ChannelNMSEExecutedReceiverCFO_Hz==hz && ...
        isequaln(row.PreRXClockChannelNMSE_dB,out.PreRXClockChannelNMSE_dB));
    if delay>0
        changed=input;
        changed.DesiredReferenceEvidence.ReceiverClockExecution. ...
            ReceiveStreamExecutionSegments{1}.Execution.RX.Replay.InjectedTimingOffset_samples=0;
        [wrong,wrongCapture]=sixgr.link.runSRSChannelEstimation(cfg,args{:},'ReceivedContext',changed);
        assert(isequaln(capture.Rx.Hest,wrongCapture.Rx.Hest) && ...
            isequaln(capture.Rx.NoiseVar,wrongCapture.Rx.NoiseVar) && ...
            isequaln(out.RIEstimate,wrong.RIEstimate) && ...
            isequaln(out.TPMIEstimate,wrong.TPMIEstimate) && ...
            isequaln(out.CQI,wrong.CQI) && abs(out.NMSE_dB-wrong.NMSE_dB)>1, ...
            'Scoring-only clock evidence cannot affect the practical receiver.');
    end
    missing=rmfield(input,'DesiredReferenceEvidence');
    try
        sixgr.link.runSRSChannelEstimation(cfg,args{:},'ReceivedContext',missing);
        error('test:MissingExpectedFailure','Shared scoring clock evidence was lost.');
    catch cause
        assert(string(cause.identifier)=="sixgr:link:SRS:MissingScoringClockEvidence");
    end
    fprintf('SRS_RX_CLOCK_SCORING_PASS delay=%g CFO=%g measuredTiming=%g NMSE=%g oldPlaneNMSE=%g\n', ...
        delay,hz,first,out.NMSE_dB,out.PreRXClockChannelNMSE_dB);
end
ok=true;
end

function b=buffer(samples,first,fs)
b=sixgr.phy.waveform.WaveformObservationBuffer(first,first+size(samples,1),fs,size(samples,2));
b.append(sixgr.phy.waveform.WaveformChunk(samples,first),fs);
end
