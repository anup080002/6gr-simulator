end

function T = localRuntimeTraceTable(cfg)
slotDuration_s = double(cfg.frame_timing.slot_duration_ms) / 1e3;
speed_mps = double(cfg.mobility.ue_speed_kmh) / 3.6;
fcHz = double(cfg.frequency.center_frequency_hz);
c = 299792458;
sitePos = [0 0 25; 500 0 25];
basePathloss = [101, 103];
shadow = [2.0, 3.0];
o2i = [0, 0];
rows = repmat(struct( ...
    "Slot", NaN, "Time_s", NaN, "UEID", NaN, "CellID", NaN, "ServingCell", NaN, ...
    "X_m", NaN, "Y_m", NaN, "Z_m", NaN, "Speed_kmh", NaN, "Speed_mps", NaN, ...
    "Heading_deg", NaN, "Heading_rad", NaN, ...
    "Distance2D_m", NaN, "Distance3D_m", NaN, "PropagationDelay_s", NaN, ...
    "RadialVelocity_mps", NaN, "ExpectedDopplerHz", NaN, "AppliedDopplerHz", NaN, "SignedDoppler_Hz", NaN, ...
    "BasePathloss_dB", NaN, "Pathloss_dB", NaN, "ShadowFading_dB", NaN, "O2I_dB", NaN, ...
    "LOSFlag", false, "LOSState", "", "PathlossModelSource", "", "PathlossComplianceStatus", "", ...
    "LOSProbabilitySource", "", "LOSComplianceStatus", "", "Status", ""), 8, 1);

rowIdx = 1;
for ue = 1:2
    for slot = 1:4
        t = double(slot - 1) * slotDuration_s;
        if ue == 1
            pos = [120 + speed_mps * t, 25, 1.5];
            headingDeg = 0;
        else
            pos = [380 - speed_mps * t, -25, 1.5];
            headingDeg = 180;
        end
        site = sitePos(ue, :);
        d2d = hypot(pos(1) - site(1), pos(2) - site(2));
        d3d = norm(pos - site);
        doppler = speed_mps * fcHz / c;
        appliedDoppler = doppler;
        pathloss = basePathloss(ue) + shadow(ue) + o2i(ue);
        rows(rowIdx) = struct( ...
            "Slot", double(slot), ...
            "Time_s", double(t), ...
            "UEID", double(ue), ...
            "CellID", double(ue), ...
            "ServingCell", double(ue), ...
            "X_m", double(pos(1)), ...
            "Y_m", double(pos(2)), ...
            "Z_m", double(pos(3)), ...
            "Speed_kmh", double(cfg.mobility.ue_speed_kmh), ...
            "Speed_mps", double(speed_mps), ...
            "Heading_deg", double(headingDeg), ...
            "Heading_rad", double(headingDeg * pi / 180), ...
            "Distance2D_m", double(d2d), ...
            "Distance3D_m", double(d3d), ...
            "PropagationDelay_s", double(d3d / c), ...
            "RadialVelocity_mps", double(speed_mps), ...
            "ExpectedDopplerHz", double(doppler), ...
            "AppliedDopplerHz", double(appliedDoppler), ...
            "SignedDoppler_Hz", double(appliedDoppler), ...
            "BasePathloss_dB", double(basePathloss(ue)), ...
            "Pathloss_dB", double(pathloss), ...
            "ShadowFading_dB", double(shadow(ue)), ...
            "O2I_dB", double(o2i(ue)), ...
            "LOSFlag", true, ...
            "LOSState", "LOS", ...
            "PathlossModelSource", "geometry_runtime_fixture", ...
            "PathlossComplianceStatus", "reconciled_fixture", ...
            "LOSProbabilitySource", "geometry_runtime_fixture", ...
            "LOSComplianceStatus", "reconciled_fixture", ...
            "Status", "runtime_trace_complete");
        rowIdx = rowIdx + 1;
    end
end

T = struct2table(rows, "AsArray", true);
end

function T = localTrialTable(direction)
rows = repmat(struct( ...
    "Direction", "", "Slot", NaN, "UEID", NaN, "CellID", NaN, ...
    "MeasuredTrialSINR_dB", NaN, "MeasuredTrialSINRSource", "", ...
    "MCS", NaN, "RankEstimate", NaN, "Layers", NaN, "Modulation", "", "Status", ""), 8, 1);
rowIdx = 1;
for ue = 1:2
    for slot = 1:4
        sinrBase = 18 + ue + 0.25 * slot;
        if upper(string(direction)) == "UL"
            sinrBase = sinrBase - 1.5;
        end
        rows(rowIdx) = struct( ...
            "Direction", upper(string(direction)), ...
            "Slot", double(slot), ...
            "UEID", double(ue), ...
            "CellID", double(ue), ...
            "MeasuredTrialSINR_dB", double(sinrBase), ...
            "MeasuredTrialSINRSource", "runtime_posteq_link_trial", ...
            "MCS", double(16 + ue + slot), ...
            "RankEstimate", double(localTernary(upper(string(direction)) == "DL", 2, 1)), ...
            "Layers", double(localTernary(upper(string(direction)) == "DL", 2, 1)), ...
            "Modulation", localTernary(upper(string(direction)) == "DL", "256QAM", "64QAM"), ...
            "Status", "PASS");
        rowIdx = rowIdx + 1;
    end
end
T = struct2table(rows, "AsArray", true);
end

function localWriteAuditPrereqs(runFolder, cfg)
layout = sixgr.report.resultLayout(runFolder);
sixgr.util.ensureFolder(layout.MetaDir);
sixgr.util.ensureFolder(layout.ReportCSVDir);
sixgr.util.jsonWrite(fullfile(layout.MetaDir, "scenario_config_resolved.json"), cfg);
runClassT = table( ...
    "ue_placement_geometry_lls", false, true, true, false, ...
    "20", "256QAM", 2, 2, 1.0, false, ...
    "ue_placement_geometry_lls uses dedicated geometry and mobility evidence gating.", ...
    'VariableNames', {'RunClass','FixedMCSActive','RankFixed','ModulationFixed','AdaptiveMode', ...
    'ConfiguredMCS','ConfiguredModulation','ConfiguredRank','ConfiguredLayers', ...
    'ExactConfiguredEffectiveMatchRate','PublicationLLSEligible','Reason'});
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, "run_classification.csv"), runClassT);
end

function out = localTernary(cond, a, b)
if cond
    out = a;
else
    out = b;
end
end

function localExerciseActualGeometryScenarioYaml()
repoRoot = pwd;
scenarioPath = fullfile(repoRoot, "simulator", "configs", "scenarios", ...
    "master_geometry_based.yaml");
baseScfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
resolved = baseScfg.toStruct();
resolved.meta.scenario_id = "master_geometry_based_focus";
resolved.meta.description = "Reduced-slot geometry runtime evidence regression";
resolved.simulation.n_slots = 4;
resolved.simulation.monte_carlo_iterations = 1;
resolved.simulation.random_seed = 91357;
resolved.run_control.total_slots = 4;
resolved.run_control.warmup_slots = 0;
resolved.run_control.measurement_slots = 4;
resolved.run_control.total_time_ms = 2.0;
resolved.run_control.warmup_time_ms = 0.0;
resolved.run_control.measurement_time_ms = 2.0;
resolved.run_control.num_workers = 1;
resolved.canonical_control.run.total_slots = 4;
resolved.canonical_control.run.warmup_slots = 0;
resolved.canonical_control.run.measurement_slots = 4;

focusScfg = sixgr.lls6g.config.ScenarioConfig(resolved, ...
    "SourceFiles", baseScfg.SourceFiles, ...
    "ConfigPath", baseScfg.ConfigPath, ...
    "ConfigHash", baseScfg.ConfigHash, ...
    "Kind", baseScfg.Kind);

tmp = tempname;
mkdir(tmp);
cleanupObj = onCleanup(@() localCleanupTempFolder(tmp)); %#ok<NASGU>
runFolder = fullfile(tmp, "run");
cfg = sixgr.lls6g.buildInternalConfig(focusScfg, runFolder);
reportConfiguration = sixgr.util.structGet(cfg, ...
    "phy.csi.reportConfiguration", struct());
assert(double(sixgr.util.structGet(reportConfiguration, "Ports", NaN)) == ...
    double(sixgr.util.structGet(cfg, "phy.csirs.nPorts", NaN)) && ...
    double(sixgr.util.structGet(reportConfiguration, ...
    "NumCSIResources", NaN)) == double(sixgr.util.structGet(cfg, ...
    "phy.csirs.numResources", NaN)), ...
    ["A disabled strict Phase-07 profile must not overwrite the active " + ...
     "geometry CSI-RS report port/resource authority."]);

ctx = sixgr.core.SimContext(cfg, "RunFolder", runFolder);
ctx.Logger.EchoToConsole = false;
systemOut = sixgr.system.SystemLevelRunner.run(ctx, struct( ...
    "PHYBackend", "waveform", ...
    "DetailedTrace", true, ...
    "NumTTI", 4, ...
    "SimDuration_s", 4 * 0.5e-3));
ctx.Logger.close();
assert(logical(systemOut.Ok), ...
    "The reduced-slot actual geometry YAML runtime must complete. Errors: %s", ...
    strjoin(cellstr(string(systemOut.Errors)), " | "));

layout = sixgr.report.resultLayout(runFolder);
sixgr.util.ensureFolder(layout.MetaDir);
sixgr.util.ensureFolder(layout.ReportCSVDir);
sixgr.util.jsonWrite(fullfile(layout.MetaDir, "scenario_config_resolved.json"), resolved);
runClassT = table( ...
    "ue_placement_geometry_lls", false, true, true, false, ...
    "20", "256QAM", 2, 2, 1.0, false, ...
    "ue_placement_geometry_lls uses dedicated geometry and mobility evidence gating.", ...
    'VariableNames', {'RunClass','FixedMCSActive','RankFixed','ModulationFixed','AdaptiveMode', ...
    'ConfiguredMCS','ConfiguredModulation','ConfiguredRank','ConfiguredLayers', ...
    'ExactConfiguredEffectiveMatchRate','PublicationLLSEligible','Reason'});
sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, "run_classification.csv"), runClassT);

sixgr.truth.exportSystemLevelCanonicalArtifacts(runFolder, focusScfg, cfg, systemOut);
sixgr.analytics.buildPhase7ReadinessArtifacts(cfg, runFolder);

for rel = [ ...
        "geometry/csv/topology_nodes.csv"
        "geometry/csv/ue_initial_positions.csv"
        "geometry/csv/trajectory_geometry.csv"
        "geometry/csv/serving_cell_assignment.csv"
        "mobility/csv/trajectory_segment_table.csv"
        "mobility/csv/doppler_reconciliation.csv"
        "mobility/csv/pathloss_reconciliation.csv"
        "mobility/csv/propagation_delay_reconciliation.csv"
        "mobility/csv/channel_continuity_reconciliation.csv"
        "reports/csv/measured_sinr_timeseries.csv"]'
    assert(exist(fullfile(runFolder, char(rel)), "file") == 2, ...
        "The actual geometry YAML runtime must emit %s.", rel);
end

trajT = readtable(fullfile(runFolder, "geometry", "csv", "trajectory_geometry.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
assert(height(trajT) == 8, ...
    "The reduced-slot actual geometry YAML runtime must emit one trajectory row per UE and slot.");
assert(all(isfinite(double(trajT.Speed_kmh))) && ...
    all(abs(double(trajT.Speed_kmh) - 200) < 1e-9), ...
    "The actual geometry YAML trajectory evidence must backfill finite 200 km/h speed rows.");
assert(all(isfinite(double(trajT.ExpectedDopplerHz))) && ...
    all(abs(double(trajT.ExpectedDopplerHz) - ...
    abs(double(trajT.RadialVelocity_mps)) .* 4.0e9 ./ 299792458) < 1e-6) && ...
    all(double(trajT.ExpectedDopplerHz) <= 741.2535448847824 + 1e-6), ...
    "The actual geometry YAML trajectory evidence must expose radial link Doppler bounded by the 200 km/h maximum Doppler.");
assert(all(isfinite(double(trajT.AppliedDopplerHz))), ...
    "The actual geometry YAML trajectory evidence must expose finite applied Doppler rows.");
assert(all(isfinite(double(trajT.Pathloss_dB))), ...
    "The actual geometry YAML trajectory evidence must expose finite pathloss rows.");
assert(all(string(trajT.Status) == "runtime_trace_complete"), ...
    "The actual geometry YAML trajectory rows must be fully populated after runtime backfill.");

audit = sixgr.validation.auditGeometryScenarioRun(runFolder, "Strict", false, "WriteOutputs", true);
assert(logical(audit.Ok), ...
    "The reduced-slot actual geometry YAML runtime must pass the geometry audit after runtime evidence export. Failures: %s", ...
    strjoin(cellstr(string(audit.FailureCodes)), " | "));
assert(~any(contains(string(audit.FailureCodes), "fixed_snr_sweep")), ...
    "The geometry audit must not claim fixed SNR sweep evidence for the geometry scenario.");

if usejava("jvm")
    plotInfo = sixgr.visual.plotGeometryScenarioEvidence(runFolder);
    assert(any(contains(string(plotInfo.GeneratedPlots), "geometry_scenario_dashboard.png")), ...
        "The actual geometry YAML evidence plot set must include geometry_scenario_dashboard.png.");
end
end

function localCleanupTempFolder(tmp)
runLog = fullfile(tmp, "run", "logs", "run.log");
if exist(runLog, "file") == 2
    fclose("all");
end
if isfolder(tmp)
    rmdir(tmp, "s");
end
end
