function ok = testGeometryScenarioAudit()
%TESTGEOMETRYSCENARIOAUDIT Geometry LLS evidence must be non-empty and fail closed.

setup6GRSimToolkit("Verbose", false);

tmp = tempname;
mkdir(tmp);
cleanupObj = onCleanup(@() rmdir(tmp, "s")); %#ok<NASGU>

cfg = localGeometryCfg();
geom = sixgr.channel.buildScenarioGeometry(cfg);
assert(height(geom.SectorTable) == 2, ...
    "buildScenarioGeometry must honor topology.num_sectors_per_site=1 for the 2-cell geometry scenario.");

traceT = localRuntimeTraceTable(cfg);
sixgr.analytics.writeAnalysisTable(fullfile(tmp, "reports", "csv", "live_rsrp_serving_trace.csv"), traceT);
sixgr.util.csvWriteTable(fullfile(tmp, "air_interface", "csv", "dl_pdsch_trials.csv"), localTrialTable("DL"));
sixgr.util.csvWriteTable(fullfile(tmp, "air_interface", "csv", "ul_pusch_trials.csv"), localTrialTable("UL"));
localWriteAuditPrereqs(tmp, cfg);

sixgr.analytics.buildPhase7ReadinessArtifacts(cfg, tmp);

for rel = [ ...
        "geometry/csv/topology_nodes.csv"
        "geometry/csv/ue_initial_positions.csv"
        "geometry/csv/trajectory_geometry.csv"
        "geometry/csv/serving_cell_assignment.csv"
        "mobility/csv/trajectory_segment_table.csv"
        "mobility/csv/doppler_reconciliation.csv"
        "mobility/csv/pathloss_reconciliation.csv"
        "mobility/csv/propagation_delay_reconciliation.csv"
        "mobility/csv/channel_continuity_reconciliation.csv"
        "reports/csv/measured_sinr_timeseries.csv"]'
    assert(exist(fullfile(tmp, char(rel)), "file") == 2, ...
        "Missing geometry evidence artifact: %s", rel);
end

topologyT = readtable(fullfile(tmp, "geometry", "csv", "topology_nodes.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
assert(sum(upper(string(topologyT.NodeClass)) == "CELL") == 2, ...
    "Topology nodes must expose two cell rows.");
assert(sum(upper(string(topologyT.NodeClass)) == "UE") == 2, ...
    "Topology nodes must expose two UE rows.");

sinrT = readtable(fullfile(tmp, "reports", "csv", "measured_sinr_timeseries.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
assert(height(sinrT) > 0 && all(isfinite(double(sinrT.MeasuredSINR_dB))), ...
    "Measured SINR timeseries must contain finite runtime SINR rows.");
assert(all(ismember(["DL","UL"], unique(upper(string(sinrT.Direction))))), ...
    "Measured SINR timeseries must expose both DL and UL evidence for this fixture.");

audit = sixgr.validation.auditGeometryScenarioRun(tmp, "Strict", false, "WriteOutputs", true);
assert(logical(audit.Ok), "A complete geometry evidence fixture must pass the geometry runtime audit.");
assert(exist(fullfile(tmp, "reports", "csv", "geometry_runtime_audit.csv"), "file") == 2, ...
    "The geometry runtime audit CSV must be written.");
assert(any(strcmp(string(audit.Table.CheckName), "fixed_snr_sweep_not_claimed")) && ...
    all(string(audit.Table.Status(string(audit.Table.CheckName) == "fixed_snr_sweep_not_claimed")) == "PASS"), ...
    "Geometry runs must explicitly pass the no-fixed-sweep-claim audit row.");

% Geometry-enabled connected truth is not the dedicated geometry campaign.
% It must still audit all physical evidence without being falsely rejected
% or relabeled as ue_placement_geometry_lls.
connectedCfg = cfg;
connectedCfg.validation.run_class = "adaptive_system_diagnostic";
connectedCfg.validation.geometry_evidence_required = false;
connectedCfg.canonical_control.launch.geometry_enabled = true;
sixgr.util.jsonWrite(fullfile(tmp, "meta", "scenario_config_resolved.json"), connectedCfg);
connectedClassT = readtable(fullfile(tmp, "reports", "csv", "run_classification.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
connectedClassT.RunClass(:) = "adaptive_system_diagnostic";
sixgr.util.csvWriteTable(fullfile(tmp, "reports", "csv", "run_classification.csv"), connectedClassT);
connectedAudit = sixgr.validation.auditGeometryScenarioRun(tmp, "Strict", false, "WriteOutputs", false);
assert(logical(connectedAudit.Required) && logical(connectedAudit.Ok), ...
    "A geometry-enabled connected truth run must audit measured geometry without requiring the dedicated campaign class.");
assert(string(connectedAudit.RunClass) == "adaptive_system_diagnostic", ...
    "The geometry audit must preserve the connected runtime class instead of relabeling it.");

% Restore the dedicated fixture for the remaining negative checks.
localWriteAuditPrereqs(tmp, cfg);

if usejava("jvm")
    plotInfo = sixgr.visual.plotGeometryScenarioEvidence(tmp);
    assert(any(contains(string(plotInfo.GeneratedPlots), "topology_map.png")), ...
        "The geometry evidence plot set must include topology_map.png when JVM plotting is available.");
    assert(any(contains(string(plotInfo.GeneratedPlots), "measured_sinr_vs_slot.png")), ...
        "The geometry evidence plot set must include measured_sinr_vs_slot.png when JVM plotting is available.");
    lineagePath = fullfile(tmp, "reports", "csv", ...
        "geometry_plot_lineage.csv");
    assert(exist(lineagePath, "file") == 2, ...
        "Geometry plots must publish exact runtime-source lineage.");
    lineageT = readtable(lineagePath, "Delimiter", ",", ...
        "VariableNamingRule", "preserve", "TextType", "string");
    assert(height(lineageT) == numel(plotInfo.GeneratedPlots) && ...
        all(string(lineageT.Status) == "PASS") && ...
        all(strlength(string(lineageT.SourceCSV_SHA256)) >= 64) && ...
        all(strlength(string(lineageT.ImageSHA256)) == 64), ...
        "Every rendered geometry image must bind exact CSV and PNG hashes.");
end

trajPath = fullfile(tmp, "geometry", "csv", "trajectory_geometry.csv");
trajT = readtable(trajPath, "VariableNamingRule", "preserve", "TextType", "string");
sixgr.util.csvWriteTable(trajPath, trajT([],:));
auditMissingTraj = sixgr.validation.auditGeometryScenarioRun(tmp, "Strict", false, "WriteOutputs", false);
assert(~logical(auditMissingTraj.Ok), "An empty trajectory file must fail the geometry runtime audit.");
assert(any(contains(string(auditMissingTraj.FailureCodes), "trajectory_geometry_empty")) || ...
    any(contains(string(auditMissingTraj.FailureCodes), "required_artifact_missing_or_empty")), ...
    "The geometry audit must explain that the trajectory evidence is missing or empty.");

localExerciseActualGeometryScenarioYaml();

ok = true;
end

