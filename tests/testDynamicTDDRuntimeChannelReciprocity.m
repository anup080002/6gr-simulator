function ok = testDynamicTDDRuntimeChannelReciprocity()
%TESTDYNAMICTDDRUNTIMECHANNELRECIPROCITY Moving CDL reciprocity and state sharing.

setup6GRSimToolkit("Verbose", false);
if exist("nrCDLChannel", "class") ~= 8
    warning("testDynamicTDDRuntimeChannelReciprocity:Missing5G", ...
        "nrCDLChannel is unavailable; skipping moving reciprocal CDL test.");
    ok = true;
    return;
end

cfg = sixgr.config.defaultConfig();
cfg.run.seed = 65537;
cfg.channel.seed = 65537;
cfg.channel.model = "CDL-A";
cfg.channel.cdlProfile = "CDL-A";
cfg.channel.delayProfile = "CDL-A";
cfg.channel.fading.model = "CDL";
cfg.channel.fading.profile = "CDL-A";
cfg.channel.delaySpread_s = 100e-9;
cfg.channel.doppler_Hz = 7.838756;
cfg.channel.channelFiltering = true;
cfg.channel.normalizePathGains = false;
cfg.channel.normalizeChannelOutputs = false;
cfg.phy.fc_Hz = 3.5e9;
cfg.phy.carrier.NSizeGrid = 25;
cfg.phy.carrier.SubcarrierSpacing = 15;
cfg.phy.duplex.mode = "TDD";
cfg.lls6g.mimo.reciprocity_mode = "TDD";
cfg.lls6g.reference_signals.operation_orientation = "tdd_reciprocity";
cfg.outputs.phySignalDiagnosticChannelPoints = 4096;

dlKey = sixgr.channel.ChannelFactory.runtimeChannelKey(cfg, "DL", ...
    "UEIndex", 1, "ServingCell", 1);
ulKey = sixgr.channel.ChannelFactory.runtimeChannelKey(cfg, "UL", ...
    "UEIndex", 1, "ServingCell", 1);
dlSeed = sixgr.channel.ChannelFactory.runtimeChannelSeed(cfg, dlKey);
ulSeed = sixgr.channel.ChannelFactory.runtimeChannelSeed(cfg, ulKey);
dlStateKey = sixgr.channel.ChannelFactory.runtimeChannelStateKey(cfg, dlKey);
ulStateKey = sixgr.channel.ChannelFactory.runtimeChannelStateKey(cfg, ulKey);
assert(sixgr.channel.ChannelFactory.supportsRuntimeTDDReciprocity(cfg) && ...
    sixgr.channel.ChannelFactory.supportsDynamicRuntimeTDDReciprocity(cfg), ...
    "Nonzero-Doppler TDD CDL must select exact dynamic reciprocity.");
assert(dlSeed == ulSeed && string(dlStateKey) == string(ulStateKey), ...
    "Moving TDD directions must share one seed and canonical state key.");
cfgPhysicalTDD = cfg;
cfgPhysicalTDD.lls6g.mimo.reciprocity_mode = "disabled_for_CSI_transfer";
cfgPhysicalTDD.lls6g.reference_signals.operation_orientation = "none";
assert(sixgr.channel.ChannelFactory.supportsDynamicRuntimeTDDReciprocity( ...
    cfgPhysicalTDD), ...
    ["Disabling CSI reciprocity use must not split the physical TDD " ...
     "propagation channel into unrelated DL and UL fading processes."]);

fs = 7.68e6;
txInfo = struct("OFDM", struct("SampleRate", fs));
nSamples = 128;
xDL = complex(zeros(nSamples, 4));
xUL = complex(zeros(nSamples, 2));
dl = sixgr.channel.ChannelFactory.createRuntimeChannelState(cfg, "DL", ...
    "LinkKey", dlKey, "Seed", dlSeed);
ul = sixgr.channel.ChannelFactory.createRuntimeChannelState(cfg, "UL", ...
    "LinkKey", ulKey, "Seed", ulSeed);
dl = sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    dl, cfg, xDL, txInfo, "NumTxAnt", 4, "NumRxAnt", 2);
ul = sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    ul, cfg, xUL, txInfo, "NumTxAnt", 2, "NumRxAnt", 4);
assert(isa(dl.Obj, "nrCDLChannel") && isa(ul.Obj, "nrCDLChannel"), ...
    "Moving reciprocity must retain the executed nrCDLChannel backend.");
assert(~dl.Obj.TransmitAndReceiveSwapped && ul.Obj.TransmitAndReceiveSwapped, ...
    "Only the UL endpoint may be reversed from the canonical DL object.");
assert(~dl.Obj.NormalizeChannelOutputs && ~ul.Obj.NormalizeChannelOutputs, ...
    "Physical per-connector power must remain unnormalized in both directions.");

[~, replayDL] = sixgr.channel.ChannelFactory.applyRuntimeChannelState( ...
    dl, xDL, "CapturePathGains", true);
[~, replayUL] = sixgr.channel.ChannelFactory.applyRuntimeChannelState( ...
    ul, xUL, "CapturePathGains", true);
pDL = replayDL.RuntimeChannelPathGainsPreview;
pUL = replayUL.RuntimeChannelPathGainsPreview;
expectedUL = permute(pDL, [1 2 4 3]);
assert(isequal(size(pUL), size(expectedUL)), ...
    "Reciprocal path-gain previews must swap only Tx/Rx dimensions.");
relativeError = norm(double(pUL(:) - expectedUL(:))) / ...
    max(norm(double(expectedUL(:))), eps);
assert(relativeError <= 1e-12, ...
    "Moving UL path gains must be the exact DL nonconjugate transpose (error %.3g).", ...
    relativeError);
assert(replayDL.RuntimeChannelAngleEvidenceAvailable && ...
    replayUL.RuntimeChannelAngleEvidenceAvailable && ...
    numel(replayDL.RuntimeChannelAnglesAoD_deg) == size(pDL, 2) && ...
    numel(replayUL.RuntimeChannelAnglesAoD_deg) == size(pUL, 2) && ...
    string(replayDL.RuntimeChannelAngleEvidenceSource) == ...
        "info_on_same_executed_runtime_channel_object", ...
    "Executed path-gain evidence must carry same-object path angles.");
assert(string(dl.Meta.RuntimeTDDReciprocityApproximationMode) == "none_dynamic_exact" && ...
    string(ul.Meta.RuntimeTDDReciprocityApproximationMode) == "none_dynamic_exact", ...
    "Moving reciprocal channel evidence must not be labeled proxy or fallback.");

infoDL = info(dl.Obj);
infoUL = info(ul.Obj);
assert(max(abs(double(infoUL.AnglesAoD(:)) - double(infoDL.AnglesAoA(:)))) <= 1e-12 && ...
    max(abs(double(infoUL.AnglesAoA(:)) - double(infoDL.AnglesAoD(:)))) <= 1e-12 && ...
    max(abs(double(infoUL.AnglesZoD(:)) - double(infoDL.AnglesZoA(:)))) <= 1e-12 && ...
    max(abs(double(infoUL.AnglesZoA(:)) - double(infoDL.AnglesZoD(:)))) <= 1e-12, ...
    "UL channel metadata must reverse AoD/AoA and ZoD/ZoA.");

% The coupled runtime must keep exactly one mutable fading clock while its
% direction changes.  Direction-specific LinkKey evidence remains intact.
runtime = struct( ...
    "CurrentServingIdx", 1, ...
    "CurrentSlot", 1, ...
    "CurrentFrame", 0, ...
    "SlotDuration_s", 1e-3, ...
    "RuntimeChannelStates", repmat( ...
        sixgr.channel.ChannelFactory.emptyRuntimeChannelState(), 0, 1));
[runtime, sharedDL] = ...
    sixgr.truth.CoupledTruthRuntime.acquireRuntimeChannelStateForControl( ...
    runtime, cfg, 1, "DL");
sharedDL = sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    sharedDL, cfg, xDL, txInfo, "NumTxAnt", 4, "NumRxAnt", 2);
runtime = sixgr.truth.CoupledTruthRuntime.commitRuntimeChannelState( ...
    runtime, sharedDL);
runtime.CurrentSlot = 2;
[runtime, sharedUL] = ...
    sixgr.truth.CoupledTruthRuntime.acquireRuntimeChannelStateForControl( ...
    runtime, cfg, 1, "UL");
assert(string(sharedUL.StateKey) == string(sharedDL.StateKey) && ...
    double(sharedUL.Seed) == double(sharedDL.Seed), ...
    "Coupled DL and UL acquisitions must recover the same reciprocal state.");
sharedUL = sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    sharedUL, cfg, xUL, txInfo, "NumTxAnt", 2, "NumRxAnt", 4);
assert(sharedUL.Obj.TransmitAndReceiveSwapped && ...
    string(sharedUL.Meta.RuntimeTDDReciprocityDirection) == "UL" && ...
    double(sharedUL.NumTxAnt) == 2 && double(sharedUL.NumRxAnt) == 4, ...
    "The shared object must retarget to the exact UL endpoint dimensions.");
runtime = sixgr.truth.CoupledTruthRuntime.commitRuntimeChannelState( ...
    runtime, sharedUL);
assert(numel(runtime.RuntimeChannelStates) == 1, ...
    "Moving TDD DL/UL must not create independent runtime fading states.");

% FDD remains physically independent even if a stale reciprocity token is
% present elsewhere in the configuration.
cfgFDD = cfg;
cfgFDD.phy.duplex.mode = "FDD";
assert(~sixgr.channel.ChannelFactory.supportsRuntimeTDDReciprocity(cfgFDD), ...
    "FDD must never enable TDD channel-state sharing.");
fddDLSeed = sixgr.channel.ChannelFactory.runtimeChannelSeed(cfgFDD, dlKey);
fddULSeed = sixgr.channel.ChannelFactory.runtimeChannelSeed(cfgFDD, ulKey);
assert(fddDLSeed ~= fddULSeed && ...
    string(sixgr.channel.ChannelFactory.runtimeChannelStateKey(cfgFDD, dlKey)) ~= ...
    string(sixgr.channel.ChannelFactory.runtimeChannelStateKey(cfgFDD, ulKey)), ...
    "FDD DL/UL must retain independent seeds and state keys.");

% Explicit receive-count normalization is incompatible with exact
% unequal-array moving reciprocity and must fail closed.
cfgBad = cfg;
cfgBad.channel.normalizeChannelOutputs = true;
bad = sixgr.channel.ChannelFactory.createRuntimeChannelState(cfgBad, "DL", ...
    "LinkKey", dlKey);
localAssertThrows(@() sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    bad, cfgBad, xDL, txInfo, "NumTxAnt", 4, "NumRxAnt", 2), ...
    "ChannelFactory:DynamicTDDOutputNormalizationForbidden");

ok = true;
end

function localAssertThrows(fcn, expectedIdentifier)
threw = false;
try
    fcn();
catch ME
    threw = true;
    assert(string(ME.identifier) == string(expectedIdentifier), ...
        "Expected %s, got %s (%s).", expectedIdentifier, ME.identifier, ME.message);
end
assert(threw, "Expected error %s was not thrown.", expectedIdentifier);
end
