function ok=testTRSStandaloneScoringTiming()
% Same practical reception: scoring must use the executed sample clock.
setup6GRSimToolkit('Verbose',false);
scenario=sixgr.lls6g.config.loadScenarioConfig( ...
    'simulator/configs/fixtures/lls_result_richness.yaml');
cfg=sixgr.lls6g.buildInternalConfig(scenario,tempname);
[out,capture]=sixgr.link.runTRSTracking(cfg,'SNR_dB',30);
assert(~out.Crash && out.NMSEScoringAvailable && out.NMSE_dB< ...
    capture.Prepared.StrictConfig.ChannelNMSEThresholddB, ...
    'Recorded RX timing must not appear as a fictitious channel error.');
assert(capture.RecordedReceiverTimingOffset_samples==16 && ...
    contains(out.ChannelNMSEReferencePlane,'recorded_RX_timing_clock'));
% Deliberately wrong scoring clock must change NMSE, not reception.
wrong=capture;
ref=capture.DesiredReferenceObservation;
wrong.DesiredReferenceObservation=localObservation(ref, ...
    sixgr.util.applyFractionalSampleDelay(ref.readComplete(),16));
bad=sixgr.link.runTRSTracking(cfg,'ReceivedContext',wrong);
assert(bad.NMSE_dB>out.NMSE_dB+10 && ~bad.Ok);
assert(isequaln(out.DetectionTable,bad.DetectionTable) && ...
    out.EstimatedTimingOffset_samples==bad.EstimatedTimingOffset_samples && ...
    out.EstimatedCFO_Hz==bad.EstimatedCFO_Hz, ...
    'Scoring references must never enter practical estimation.');
% Gain errors must remain observable; do not normalize Hest to the truth.
wrong=capture;
wrong.Observation=localObservation(capture.Observation, ...
    2*capture.Observation.readComplete());
badGain=sixgr.link.runTRSTracking(cfg,'ReceivedContext',wrong);
assert(badGain.NMSE_dB>capture.Prepared.StrictConfig.ChannelNMSEThresholddB);
fprintf('TRS same-clock NMSE %.3f dB; wrong-clock %.3f dB; gain-error %.3f dB.\n', ...
    out.NMSE_dB,bad.NMSE_dB,badGain.NMSE_dB);
ok=true;
end

function observation=localObservation(original,waveform)
observation=sixgr.phy.waveform.WaveformObservationBuffer( ...
    original.StartSample,original.EndSampleExclusive,original.SampleRateHz, ...
    original.NumReceiveAntennas);
observation.append(sixgr.phy.waveform.WaveformChunk(waveform,original.StartSample), ...
    original.SampleRateHz);
end
