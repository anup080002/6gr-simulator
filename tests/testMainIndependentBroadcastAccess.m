function ok=testMainIndependentBroadcastAccess()
% Actual production bundle: delayed SI before/after and first-occasion SI.
% No copied completion callback, preconfigured received SI, forced beam or
% fabricated DTX. This checks SI-dependent Msg1 admission, not full RA/data.
setup6GRSimToolkit('Verbose',false);
root=fileparts(fileparts(mfilename('fullpath')));
folder=fullfile(root,'results','validation','main_independent_broadcast_access', ...
    char(java.util.UUID.randomUUID()));
mkdir(folder); fprintf('MAIN_INDEPENDENT_BROADCAST_ACCESS_EVIDENCE %s\n',folder);
assert(strlength(strtrim(string(getenv('SIXGR_PROFILE_MODE'))))==0, ...
    'sixgr:test:UnexpectedRuntimeShortcut','Do not run this regression with a profile stop/shortcut.');
originalRNG=rng; restore=onCleanup(@()rng(originalRNG)); %#ok<NASGU>
path=fullfile(root,'simulator','configs','validation','main_independent_broadcast_access.yaml');
scenario=sixgr.lls6g.config.loadScenarioConfig(path);
earlyScenario=sixgr.lls6g.config.loadScenarioConfig(fullfile(root, ...
    'simulator','configs','validation','main_early_broadcast_access.yaml'));
earlyCfg=sixgr.lls6g.buildInternalConfig(earlyScenario,fullfile(folder,'early_planning'));
cfg=sixgr.lls6g.buildInternalConfig(scenario,fullfile(folder,'planning'));
assert(cfg.run.totalSlots==40 && cfg.phy.sib1.enable && cfg.phy.ssb.enable && ...
    cfg.phy.carrier.SubcarrierSpacing==15 && cfg.phy.carrier.NSizeGrid==25);
assert(~logical(sixgr.util.structGet(cfg,'run.runtimeCheckpointEnabled',false)) && ...
    strlength(string(sixgr.util.structGet(cfg,'run.runtimeCheckpointResumeFrom','')))==0);
plan=sixgr.phy.frame.CommonDLResourcePlan(cfg); plan.validateSIB1References();
calendar=plan.sib1TransmissionOccasions(0,cfg.run.totalSlots);
assert(height(calendar)==4 && numel(unique(calendar.SSBIndex))==4 && ...
    all(calendar.RecurrenceIndex0Based==0) && all(calendar.PeriodSlots==20), ...
    'sixgr:test:UnexpectedAccessCalendar','Keep four original associations and native20ms SI recurrence.');
slotDuration=sixgr.time.slotDurationSec(cfg);
captureSeconds=double(scenario.get('initial_access.ssb.observation_subframes'))*1e-3;
% This is a conservative experiment boundary, not a fabricated availability
% clock. Every operational availability assertion below uses actual receipts.
afterCapture=ceil(captureSeconds/slotDuration)+2;
preparationSlots=find(arrayfun(@(n)sixgr.truth.isPRACHWaveformPreparationSlot(cfg,n), ...
    1:cfg.run.totalSlots));
early=preparationSlots(preparationSlots>=afterCapture & preparationSlots<=min(calendar.AbsoluteSlot));
afterSI=max(calendar.AbsoluteSlot)+3;
late=preparationSlots(preparationSlots>=afterSI);
assert(~isempty(early) && ~isempty(late), ...
    'sixgr:test:UnboundedAccessFixture','Need native PRACH preparation both before and after first SI.');
horizons=[early(1),late(1)+3];
assert(horizons(2)<=cfg.run.totalSlots && horizons(1)<min(calendar.AbsoluteSlot)+1, ...
    'sixgr:test:UnboundedAccessFixture','Do not extend the bounded fixture to manufacture success.');
earlyPlan=sixgr.phy.frame.CommonDLResourcePlan(earlyCfg);
earlyCalendar=earlyPlan.sib1TransmissionOccasions(0,earlyCfg.run.totalSlots);
firstSI=earlyCalendar(earlyCalendar.RecurrenceIndex0Based==0,:);
assert(height(firstSI)==4 && max(firstSI.AbsoluteSlot)<min(calendar.AbsoluteSlot));
earlyPreparation=preparationSlots(preparationSlots>=max(firstSI.AbsoluteSlot)+3);
assert(~isempty(earlyPreparation),'sixgr:test:UnboundedAccessFixture','Keep a native post-SI PRACH preparation.');
horizons(3)=earlyPreparation(1)+3;
files=unique([scenario.SourceFiles; earlyScenario.SourceFiles; string(mfilename('fullpath'))+".m"; ...
    string(which('sixgr.truth.runWaveformLinkBundle')); ...
    string(which('sixgr.truth.CoupledWaveformStream')); ...
    string(which('sixgr.truth.ReceivedMIBDelivery')); ...
    string(which('sixgr.truth.ReceivedSSBTimingDelivery')); ...
    string(which('sixgr.phy.frame.SSBAcquisitionWindow')); ...
    string(which('sixgr.truth.SIB1ResultDelivery')); ...
    string(which('sixgr.runtime.resolveExecutionIdentity')); ...
    string(which('sixgr.truth.bindSharedRAPowerReference'))],'stable');
hashes=arrayfun(@(f)string(sixgr.util.sha256File(f)),files);
sixgr.util.csvWriteTable(fullfile(folder,'source_hashes.csv'), ...
    table(files,hashes,'VariableNames',{'Path','SHA256'}),'PreserveSchema',true);
resolvedScenario=scenario.toStruct(); seed=cfg.run.seed; %#ok<NASGU>
save(fullfile(folder,'original_configuration.mat'),'resolvedScenario','cfg','calendar','horizons','seed');
copyfile(path,fullfile(folder,'original_fixture.yaml'));
names=["before_SI","after_SI","first_legal_SI"];
executionIDs=strings(1,3);
[~,experimentID]=fileparts(folder);
for k=1:3
    armFolder=fullfile(folder,names(k)); mkdir(armFolder);
    armScenario=scenario;
    if k==3, armScenario=earlyScenario; end
    % This test invokes the lower-level bundle instead of runSingle. Install
    % the same immutable lifecycle inputs BEFORE producing any observations;
    % never append an identity to old receiver rows to make export pass.
    runTag="main_independent_broadcast_access_"+string(experimentID)+"_"+names(k);
    identity=sixgr.runtime.resolveExecutionIdentity( ...
        armFolder,runTag,string(armScenario.ConfigHash),struct());
    executionIDs(k)=identity.ExecutionID;
    armCfg=sixgr.lls6g.buildInternalConfig(armScenario,armFolder);
    armCfg.run.runTag=char(identity.RunID);
    armCfg.run.executionID=char(identity.ExecutionID);
    armCfg.meta.executionID=char(identity.ExecutionID);
    armCfg.run.scenarioID=char(armScenario.ScenarioID);
    armCfg.meta.scenarioID=char(armScenario.ScenarioID);
    armCfg.meta.configHash=char(identity.ConfigHash);
    persisted=jsondecode(fileread(fullfile(armFolder,'meta','execution_identity.json')));
    assert(string(persisted.ExecutionID)==identity.ExecutionID && ...
        string(persisted.RunID)==runTag && string(persisted.ConfigHash)==identity.ConfigHash);
    % Exercise the actual lifecycle binder before any costly PHY work. This
    % one-row metadata probe is NOT received evidence, is never exported and
    % never enters a primary trial table or acceptance population.
    lifecycleProbe=sixgr.truth.bindCoupledExecutionIdentity( ...
        table("fixture_lifecycle_preflight_not_PHY",'VariableNames',{'ProbeScope'}), ...
        armCfg,"PBCH",true);
    assert(all(ismember(["RunID","ExecutionID","ConfigHash","ScenarioID", ...
        "EvidenceScope","SameScenarioInPathEligible"],string(lifecycleProbe.Properties.VariableNames))) && ...
        lifecycleProbe.RunID==identity.RunID && lifecycleProbe.ExecutionID==identity.ExecutionID && ...
        lifecycleProbe.ConfigHash==identity.ConfigHash && lifecycleProbe.ScenarioID==armScenario.ScenarioID && ...
        lifecycleProbe.EvidenceScope=="in_path" && lifecycleProbe.SameScenarioInPathEligible, ...
        'sixgr:test:IncompleteFixtureLifecycle','Install the same full immutable lifecycle as runSingle before execution.');
    clear lifecycleProbe
    options=struct('LinkSNR_dB',armCfg.channel.snr_dB, ...
        'LinkSNRGrid_dB',armCfg.channel.snr_dB, ...
        'LinkDuration_s',horizons(k)*slotDuration,'LinkMaxSimFrames',horizons(k), ...
        'LinkSweepTrialsPerSNR',horizons(k),'LinkSweepFrames',1, ...
        'LinkAdaptiveSweepEnabled',false,'LinkFixedLinkCampaignEnabled',false, ...
        'FixedLinkCampaignOnly',false,'HARQDiagnosticsEnabled',false, ...
        'SaveFigures',false,'LiveCSVPNGEnabled',false,'PersistenceEnabled',true);
    rng(double(armCfg.run.seed),'twister'); initialRNG=rng; %#ok<NASGU>
    save(fullfile(armFolder,'original_execution_inputs.mat'),'armCfg','options','initialRNG','identity');
    try
        out=sixgr.truth.runWaveformLinkBundle(armCfg,fullfile(armFolder,'air_interface'),options);
        s=out.RawTrials.CoupledRuntime;
        evidence=snapshot(out,s); %#ok<NASGU>
        % Preserve actual inputs/outcomes before assertions, including a
        % finite-horizon bundle's unmet broader KPI/attachment conditions.
        save(fullfile(armFolder,'original_terminal_evidence.mat'),'evidence','-v7.3');
        checkAcquired(s,horizons(k));
        if k==1, checkBeforeSI(s,armCfg); else, checkAfterSI(s,armCfg); end
        if k==3, checkEarlyAcquisition(s,armCfg,firstSI,captureSeconds); end
        publication=checkPublished(armFolder,out,s,identity); %#ok<NASGU>
        save(fullfile(armFolder,'original_publication_checks.mat'),'publication');
        fprintf('MAIN_INDEPENDENT_BROADCAST_ACCESS_ARM_PASS arm=%s slots=%d full_RA_claim=0\n', ...
            names(k),horizons(k));
    catch cause
        failure=struct('Identifier',string(cause.identifier),'Message',string(cause.message), ...
            'Report',string(getReport(cause,'extended','hyperlinks','off'))); %#ok<NASGU>
        save(fullfile(armFolder,'failure.mat'),'failure');
        rethrow(cause);
    end
end
assert(numel(unique(executionIDs))==3, ...
    'sixgr:test:ReusedIndependentExecutionIdentity','Each separately executed arm needs its own execution identity.');
assert(isequal(hashes,arrayfun(@(f)string(sixgr.util.sha256File(f)),files)), ...
    'sixgr:test:SourceChangedDuringExecution','Preserve the original tested source/config snapshot.');
ok=true;
fprintf('MAIN_INDEPENDENT_BROADCAST_ACCESS_PASS actual_bundle=3 no_preSI_RA=1 actual_first_SI=1 actual_Msg1_RX=1 root=%s\n',folder);
end

function checkEarlyAcquisition(s,cfg,firstSI,captureSeconds)
[current,~,b]=sixgr.truth.ReceivedMIBDelivery.current(s,1);
assert(current);
fs=b.SampleRateHz; archiveEnd=round(captureSeconds*fs);
selected=firstSI(firstSI.SSBIndex==b.Context.Data.SSBIndex,:);
assert(height(selected)==1);
carrier=sixgr.phy.grid.makeCarrier(cfg);
firstSIStart=sixgr.phy.frame.slotStartSample(carrier,selected.AbsoluteSlot,fs);
assert(b.CaptureStartSample==0 && b.CaptureEndSampleExclusive<archiveEnd && ...
    b.DeliveredAvailableSample<firstSIStart, ...
    'sixgr:test:AcquisitionStillWaitsForArchive','Original MIB must be delivered before its first SI, independently of the full archive.');
accepted=s.SharedSIB1ReceptionTable(s.SharedSIB1ReceptionTable.Installed,:);
assert(any(accepted.ResourceAbsoluteSlot0Based==selected.AbsoluteSlot), ...
    'sixgr:test:MissedFirstSI','Require actual CRC/ASN.1-accepted first native SI, not a later repeated occasion.');
archive=sixgr.util.structGet(s,'SharedSSBArchiveReceipts',{});
matched=cellfun(@(r)r.AcquisitionObservationID==b.ObservationID,archive);
assert(nnz(matched)==1,'sixgr:test:MissingFullSSBArchive','Retain exactly one independent complete archive.');
a=archive{find(matched,1)};
assert(a.StartSample==0 && a.EndSampleExclusive==archiveEnd && ~a.ReceiverExecuted && ...
    a.CompletedAtSample==archiveEnd && b.DeliveredAvailableSample<a.CompletedAtSample);
for k=1:numel(a.Planes)
    p=a.Planes{k};
    assert(sixgr.phy.waveform.CompletedSampleArchive.verifyFile(p.Archive)==p.Archive.Manifest.SampleSHA256 && ...
        p.Archive.Manifest.SampleSize(1)==archiveEnd);
end
T=s.ControlTrials.PBCH;
initial=T(T.ObservationStartSample==0,:);
assert(height(initial)==a.AcquisitionWindowContract.Lmax && ...
    numel(unique(initial.RequestedSSBOccasionIndex))==height(initial) && ...
    nnz(initial.SelectedBeamFlag)==1 && ...
    all(initial.ObservationEndSampleExclusive==b.CaptureEndSampleExclusive) && ...
    all(initial.SSBReceiverSearchComplete), ...
    'sixgr:test:DuplicateAcquisitionDelivery','The later full archive must never repeat acquisition/MIB/beam delivery.');
end

function checkAcquired(s,horizon)
assert(s.CompletedCanonicalSlots==horizon && s.NumUsers==1 && ...
    string(s.CellAcquisitionState(1))=="acquired");
[current,~,b]=sixgr.truth.ReceivedMIBDelivery.current(s,1);
assert(current && b.Delivered && b.CaptureEndSampleExclusive<=b.DeliveredAvailableSample && ...
    strlength(b.DecoderInputSHA256)==64 && b.Context.Data.OriginalStrictReceiverEvidenceOk);
T=s.ControlTrials.PBCH;
require(T,["BroadcastRecoveryScope","SIB1ReceptionAttempted","BCHCrcPass","PBCHStrictReceiverEvidenceOk"]);
assert(~isempty(T) && all(string(T.BroadcastRecoveryScope)=="SSB_MIB") && ...
    all(T.SIB1ReceptionAttempted==0) && any(T.BCHCrcPass==1 & T.PBCHStrictReceiverEvidenceOk==1), ...
    'sixgr:test:MissingActualBCH','Require actual SSB-only BCH reception, not a combined-SI success label.');
end

function checkBeforeSI(s,cfg)
assert(emptyCell(s,'UECommonCellConfigurationByUE') && emptyCell(s,'DecodedSIB1RecoveryByUE') && ...
    emptyCell(s,'RARetryByUE') && emptyCell(s,'PendingRAAttempts') && s.LastPRACHSlotByUE(1)==0);
assert(isempty(sixgr.util.structGet(s,'ControlTrials.PRACH',table())) && ...
    isempty(sixgr.util.structGet(s,'ControlTrials.RAEvidenceTables.ra_receiver_rf_observations',table())));
SI=sixgr.util.structGet(s,'SharedSIB1ReceptionTable',table());
if ~isempty(SI), assert(~any(SI.Installed)); end % Actual monitoring misses are retained, never invented.
D=s.ControlTrials.RAEvidenceTables.ra_power_reference_decisions;
require(D,["ReferenceUsable","Status","Slot"]);
assert(~isempty(D) && all(~D.ReferenceUsable) && ...
    all(string(D.Status)=="no_available_decoded_sib1") && ...
    all(arrayfun(@(slot)sixgr.truth.isPRACHWaveformPreparationSlot(cfg,slot),double(D.Slot))), ...
    'sixgr:test:MissingSIDidNotDefer','Missing received SI must defer at the real caller before creating an attempt.');
end

function checkAfterSI(s,cfg)
SI=s.SharedSIB1ReceptionTable;
require(SI,["Installed","DCICrcPass","DLSCHCrcPass","SIB1ASN1DecodeOk", ...
    "SIB1SemanticValid","NewBCHReceptionAttempted","PriorBCHContextSHA256", ...
    "SIB1RxTreeHash","DeliverySlot1Based","UEId","ServingCell","ReceivedMIBGenerationID"]);
accepted=SI(SI.Installed,:);
assert(~isempty(accepted) && all(accepted.DCICrcPass==1 & accepted.DLSCHCrcPass==1 & ...
    accepted.SIB1ASN1DecodeOk==1 & accepted.SIB1SemanticValid==1) && ...
    all(accepted.NewBCHReceptionAttempted==0) && all(strlength(string(accepted.PriorBCHContextSHA256))==64));
[current,~,binding]=sixgr.truth.ReceivedMIBDelivery.current(s,1);
assert(current && all(string(accepted.PriorBCHContextSHA256)==binding.ContextSHA256) && ...
    all(string(accepted.ReceivedMIBGenerationID)==binding.GenerationID));
common=s.UECommonCellConfigurationByUE{1};
assert(string(common.Source)=="decoded_sib1" && any(string(accepted.SIB1RxTreeHash)==string(common.TreeHash)));
RF=s.ControlTrials.RAEvidenceTables.ra_receiver_rf_observations;
require(RF,["StageName","RuntimeUEIndex","ServingCell","RuntimeSlot", ...
    "ObservationStartSample","ObservationEndSampleExclusive","ResultAvailableAtSample", ...
    "RunId","UEId","AttemptId","AbsoluteSlot0","ObservationID"]);
msg1=RF(string(RF.StageName)=="Msg1",:);
assert(~isempty(msg1) && all(msg1.RuntimeUEIndex==1 & msg1.ServingCell==s.CurrentServingIdx(1)) && ...
    all(msg1.ObservationStartSample<msg1.ObservationEndSampleExclusive & ...
    msg1.ObservationEndSampleExclusive<=msg1.ResultAvailableAtSample));
D=s.ControlTrials.RAEvidenceTables.ra_power_reference_decisions;
require(D,["ReferenceUsable","Status","Slot","SIB1AvailableSlot","SIB1RxTreeHash", ...
    "UEId","ServingCell","ReferenceConfigurationEpoch","SelectedSSBIndex", ...
    "SelectedSSBTimingAvailable","SelectedSSBTimingStatus","SelectedSSBTimingObservationID", ...
    "SelectedSSBTimingBindingSHA256","SelectedSSBTimingCaptureEndSample", ...
    "SelectedSSBTimingDeliveredAtSample","SelectedSSBTimingAcquisitionGenerationID"]);
admitted=D(D.ReferenceUsable,:);
assert(~isempty(admitted) && all(admitted.SIB1AvailableSlot<=admitted.Slot) && ...
    all(ismember(string(admitted.SIB1RxTreeHash),string(accepted.SIB1RxTreeHash))) && ...
    all(arrayfun(@(slot)sixgr.truth.isPRACHWaveformPreparationSlot(cfg,slot),double(admitted.Slot))) && ...
    ~emptyCell(s,'RARetryByUE'));
carrier=sixgr.phy.grid.makeCarrier(cfg);
detected=sixgr.util.structGet(s,'ControlTrials.RAEvidenceTables.msg1_prach_detection',table());
assert(~isempty(detected),'sixgr:test:MissingActualMsg1Outcome', ...
    'Retain the actual PRACH receiver outcome; a queued transmission/RF receipt alone is insufficient.');
require(detected,["RunId","UEId","AttemptId","Msg1ScheduledSlot","AssociatedSSBIndex","OccasionID"]);
assert(numel(unique(string(msg1.ObservationID)))==height(msg1) && ...
    height(unique(msg1(:,{'RunId','UEId','AttemptId'})))==height(msg1) && ...
    height(detected)==height(msg1), ...
    'sixgr:test:DuplicateMsg1Outcome','Each original completed Msg1 attempt needs exactly one receiver outcome.');
% This is the existing NEW-attempt caller's identity convention, checked
% against original RF records. It does not create or publish another ID.
expectedRunIDs="shared_ra_ue"+string(admitted.UEId)+"_slot"+string(admitted.Slot);
for j=1:height(msg1)
    rf=msg1(j,:);
    matched=detected(string(detected.RunId)==string(rf.RunId) & ...
        detected.UEId==rf.UEId & detected.AttemptId==rf.AttemptId,:);
    assert(height(matched)==1 && strlength(string(matched.OccasionID))>0 && ...
        matched.Msg1ScheduledSlot==rf.AbsoluteSlot0 && rf.RuntimeSlot==rf.AbsoluteSlot0+1, ...
        'sixgr:test:Msg1ReceiverIdentityMismatch','Join original attempts and exact zero-based radio clocks.');
    % CellId in the PRACH decoder is PCI, not installed ServingCell index.
    % Do not equate these distinct namespaces or treat detection as success.
    decision=admitted(expectedRunIDs==string(rf.RunId) & ...
        admitted.UEId==rf.UEId & admitted.ServingCell==rf.ServingCell,:);
    assert(height(decision)==1 && decision.SelectedSSBIndex==matched.AssociatedSSBIndex && ...
        decision.ReferenceConfigurationEpoch==cfg.initial_access.configuration_epoch && ...
        rf.RuntimeSlot>=decision.Slot, ...
        'sixgr:test:Msg1AdmissionIdentityMismatch','Every completed attempt needs its own original admission.');
    received=accepted(string(accepted.SIB1RxTreeHash)==string(decision.SIB1RxTreeHash) & ...
        accepted.UEId==decision.UEId & accepted.ServingCell==decision.ServingCell & ...
        accepted.DeliverySlot1Based==decision.SIB1AvailableSlot,:);
    assert(height(received)==1 && ...
        string(received.ReceivedMIBGenerationID)==binding.GenerationID, ...
        'sixgr:test:Msg1SIIdentityMismatch','The admission must name the original installed SI delivery.');
    history=s.ReceivedSSBTimingByUE{decision.UEId};
    selected=cellfun(@(r)r.BindingSHA256==string(decision.SelectedSSBTimingBindingSHA256),history);
    assert(nnz(selected)==1,'sixgr:test:Msg1TimingIdentityMismatch', ...
        'Each Msg1 admission must name exactly one original delivered timing receipt.');
    timing=history{find(selected,1)};
    sixgr.truth.ReceivedSSBTimingDelivery.validate(timing,true);
    admissionSample=sixgr.phy.frame.slotStartSample(carrier,decision.Slot-1,s.SharedWaveformStream.SampleRateHz);
    assert(decision.SelectedSSBTimingAvailable && ...
        string(decision.SelectedSSBTimingStatus)=="current_delivered_selected_ssb_timing" && ...
        timing.SSBIndex==decision.SelectedSSBIndex && ...
        timing.OriginalBCHBinding.ObservationID==string(decision.SelectedSSBTimingObservationID) && ...
        timing.OriginalBCHBinding.CaptureEndSampleExclusive==decision.SelectedSSBTimingCaptureEndSample && ...
        timing.DeliveredAvailableSample==decision.SelectedSSBTimingDeliveredAtSample && ...
        timing.AcquisitionGenerationID==string(decision.SelectedSSBTimingAcquisitionGenerationID) && ...
        timing.AcquisitionGenerationID==string(received.ReceivedMIBGenerationID) && ...
        timing.DeliveredAvailableSample<=admissionSample && ...
        timing.DeliveredAvailableSample<=rf.ObservationStartSample, ...
        'sixgr:test:Msg1TimingIdentityMismatch','Do not reconstruct, retag or deliver selected timing after its use.');
    available=sixgr.phy.frame.slotStartSample(carrier, ...
        received.DeliverySlot1Based-1,s.SharedWaveformStream.SampleRateHz);
    assert(rf.ObservationStartSample>=available, ...
        'sixgr:test:Msg1BeforeReceivedSI','Use this attempt''s original SI availability, not the earliest unrelated SI.');
end
end

function receipts=checkPublished(folder,out,s,identity)
% Inspect only files produced by the main runner. Never call an exporter or
% reconstruct a CSV here to conceal missing production publication.
layout=sixgr.report.resultLayout(folder);
SI=sixgr.util.structGet(s,'SharedSIB1ReceptionTable',table());
assert(~any(ismember(["BCHCrcPass","MIBDecoded","PBCHStrictReceiverEvidenceOk"], ...
    string(SI.Properties.VariableNames))));
receipts=checkCSV(fullfile(layout.AirInterfaceCSVDir,'sib1_received_trials.csv'), ...
    SI,string(SI.Properties.VariableNames),true);
PBCH=out.RawTrials.PBCH; % Final canonical table, not the pre-publication state.
fields=["BroadcastRecoveryScope","SIB1ReceptionAttempted","BCHCrcPass", ...
    "PBCHStrictReceiverEvidenceOk","Status","RunID","ExecutionID","ConfigHash"];
require(PBCH,fields);
assert(all(string(PBCH.BroadcastRecoveryScope)=="SSB_MIB") && all(PBCH.SIB1ReceptionAttempted==0));
for name=["RunID","ExecutionID","ConfigHash"]
    assert(all(string(PBCH.(name))==string(identity.(name))), ...
        'sixgr:test:PublicationIdentityMismatch','Original PBCH %s must retain the pre-execution identity.',name);
end
% Preserve additional original scalar identities if populated. The legacy
% PBCH writer prunes all-blank columns; this does not manufacture old IDs.
optional=["Slot","Frame","UEIndex","ServingCell","RNTI","RunUUID","ConfigHash", ...
    "ReceiverObservationSHA256","ReceiverObservationHashPlane","ObservationStartSample", ...
    "ObservationEndSampleExclusive","ObservationSampleRateHz"];
for name=optional
    if ~ismember(name,string(PBCH.Properties.VariableNames)), continue; end
    value=PBCH.(name);
    if isstring(value) && any(~ismissing(value) & strlength(value)>0)
        fields(end+1)=name; %#ok<AGROW>
    elseif (isnumeric(value)||islogical(value)) && iscolumn(value) && any(isfinite(value))
        fields(end+1)=name; %#ok<AGROW>
    end
end
assert(string(out.RawTrials.PBCHPath)==string(fullfile(layout.AirInterfaceCSVDir,'pbch_trials.csv')));
receipts(end+1)=checkCSV(out.RawTrials.PBCHPath,PBCH,fields,false);
names=["ra_power_reference_decisions","ra_receiver_rf_observations","msg1_prach_detection"];
columns={ ...
    ["UEId","Slot","ServingCell","SelectedSSBIndex","ReferenceConfigurationEpoch", ...
    "ReferenceUsable","Status","SIB1AvailableSlot","SIB1RxTreeHash", ...
    "SelectedSSBTimingAvailable","SelectedSSBTimingStatus","SelectedSSBTimingObservationID", ...
    "SelectedSSBTimingBindingSHA256","SelectedSSBTimingCaptureEndSample", ...
    "SelectedSSBTimingDeliveredAtSample","SelectedSSBTimingAcquisitionGenerationID"], ...
    ["RunId","UEId","RuntimeUEIndex","ServingCell","AttemptId","ObservationID", ...
    "StageName","Direction","AbsoluteSlot0","RuntimeSlot","ObservationStartSample", ...
    "ObservationEndSampleExclusive","ObservationSampleRateHz","ResultAvailableAtSample"], ...
    ["RunId","UEId","AttemptId","CellId","Msg1ScheduledSlot","AssociatedSSBIndex","OccasionID"]};
for j=1:numel(names)
    expected=sixgr.util.structGet(out.RawTrials.RAEvidenceTables,names(j),table());
    receipts(end+1)=checkCSV(fullfile(layout.ControlCSVDir,names(j)+".csv"), ...
        expected,columns{j},false); %#ok<AGROW>
end
end

function receipt=checkCSV(path,expected,columns,fullSchema)
path=string(path);
receipt=struct('Path',path,'SHA256',"",'RowCount',height(expected), ...
    'Present',isfile(path),'CheckedColumns',columns);
if ~isfile(path)
    assert(isempty(expected),'sixgr:test:MissingMainPublication','Missing original output %s.',path);
    return;
end
before=string(sixgr.util.sha256File(path));
types=struct();
for name=intersect(columns,string(expected.Properties.VariableNames),'stable')
    if isstring(expected.(name)), types.(name)='string'; end
end
read=sixgr.util.csvReadTable(path,'ColumnTypes',types);
assert(before==string(sixgr.util.sha256File(path)), ...
    'sixgr:test:OriginalPublicationChanged','Reading must not rewrite original CSV bytes.');
receipt.SHA256=before;
assert(height(read)==height(expected),'sixgr:test:MainPublicationPopulation', ...
    'Original observation population changed in %s.',path);
if isempty(expected), return; end
require(expected,columns); require(read,columns);
if fullSchema
    assert(isequal(read.Properties.VariableNames,expected.Properties.VariableNames), ...
        'sixgr:test:MainPublicationSchema','Original SI columns changed.');
end
for name=columns
    original=expected.(name); value=read.(name);
    if isstring(original)
        assert(isstring(value)); value(ismissing(value))="";
        assert(isequal(value,original),'sixgr:test:MainPublicationText','Original %s changed in %s.',name,path);
    else
        assert((isnumeric(value)||islogical(value)) && isreal(value) && ...
            isequal(size(value),size(original)) && isequaln(double(value),double(original)), ...
            'sixgr:test:MainPublicationOperand','Original %s changed in %s.',name,path);
    end
end
% SI uses RoundTripNumericText. Other checks intentionally select integer
% clocks, flags and identity strings, not rounded legacy analog metrics.
end

