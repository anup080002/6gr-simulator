function ok = testRASIPDSCHStrictOwnership()
%TESTRASIPDSCHSTRICTOWNERSHIP Common procedures use one canonical PDSCH.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
cfg = raStrictAnchorConfig();
ra = sixgr.mac.ra.RAConfig(cfg, ...
    "RunId", "ra_si_pdsch_strict", ...
    "ScenarioName", "ra_si_pdsch_strict", ...
    "UEId", 1, "AttemptId", 1);

ulGrant = sixgr.mac.ra.buildRARULGrant(ra);
rar = sixgr.mac.ra.encodeMACRAR( ...
    "RAPID", double(ra.PreambleIndex), ...
    "TimingAdvanceCommand", 0, ...
    "TemporaryCRNTI", double(ra.TempCRNTI), ...
    "ULGrant", ulGrant);
[msg2Tx,msg2Schedule] = sixgr.phy.ra. ...
    generateMsg2RARWaveform(cfg,ra,rar);
[msg2Rx,rarRx] = sixgr.phy.ra.recoverMsg2RAR( ...
    msg2Tx.Waveform,cfg,ra,msg2Schedule,msg2Tx);
localAssertStrict(msg2Tx.PDSCH,msg2Rx,"msg2_rar");
% Explicit unit-channel spatial fixture, not shared RF qualification. Feed
% all four branches to the receiver, without transmitter-weight combining.
unitSpatialRow=[1 1i -1 -1i]/2;
[msg2Diversity,rarDiversity]=sixgr.phy.ra.recoverMsg2RAR( ...
    msg2Tx.Waveform*unitSpatialRow,cfg,ra,msg2Schedule,msg2Tx);
localAssertStrict(msg2Tx.PDSCH,msg2Diversity,"msg2_rar");
localAssertReceiveDiversity(msg2Diversity);
% Absent RAR backoff is represented by NaN in both decoded structures.
assert(isequal(msg2Diversity.TransportBlock,msg2Rx.TransportBlock) && ...
    isequaln(rarDiversity,rarRx));
localAssertCommonReference(msg2Tx.PDSCH.IntegrationBinding,0,"msg2_rar");
localAssertCommonReference(msg2Rx.IntegrationBinding,0,"msg2_rar");
badIntegration=msg2Tx.PDSCHIntegrationContext;
badIntegration=rmfield(badIntegration,'CommonQCLReference');
localVerifyError(@() sixgr.pdsch.PDSCHIntegrationValidator.bind( ...
    msg2Tx.PDSCHAssignment,badIntegration,msg2Tx.PDSCHPrecoderBundle), ...
    "sixgr:pdsch:MissingCommonQCLReference");
badIntegration=msg2Tx.PDSCHIntegrationContext;
badIntegration.CommonQCLReference.ServingCellId=99;
localVerifyError(@() sixgr.pdsch.PDSCHIntegrationValidator.bind( ...
    msg2Tx.PDSCHAssignment,badIntegration,msg2Tx.PDSCHPrecoderBundle), ...
    "sixgr:pdsch:CommonQCLAssignmentMismatch");
badIntegration=msg2Tx.PDSCHIntegrationContext;
badIntegration.ActivatedTCIStates=struct('TCIStateId',0,'Activated',true);
localVerifyError(@() sixgr.pdsch.PDSCHIntegrationValidator.bind( ...
    msg2Tx.PDSCHAssignment,badIntegration,msg2Tx.PDSCHPrecoderBundle), ...
    "sixgr:pdsch:InvalidCommonQCLReference");
assert(double(rarRx.RAPID) == double(ra.PreambleIndex));
assert(string(msg2Tx.PDSCHControlEvent.Id) == ...
    string(msg2Rx.PDCCHControlEvent.Id), ...
    "Msg2 TX schedule and RX decode must bind to the same DCI event identity.");
localAssertDataIndices(msg2Tx.Carrier,msg2Schedule.PDSCH, ...
    msg2Tx.PDSCHResourcePlan);

msg3 = sixgr.mac.ra.buildMsg3Payload("UEId",1);
msg4 = sixgr.mac.ra.buildMsg4ContentionResolution( ...
    msg3.ContentionIdentity,"FinalCRNTI",double(ra.FinalCRNTI));
[msg4Tx,msg4Schedule] = sixgr.phy.ra. ...
    generateMsg4Waveform(cfg,ra,msg4);
[controlRx,msg4Rx,msg4Decoded] = sixgr.phy.ra. ...
    recoverMsg4Waveform(msg4Tx.Waveform,cfg,ra,msg4Schedule,msg4Tx);
assert(logical(controlRx.CausalGrantDecodeOk));
localAssertStrict(msg4Tx.PDSCH,msg4Rx, ...
    "msg4_contention_resolution");
[controlDiversity,msg4Diversity,decodedDiversity]=sixgr.phy.ra.recoverMsg4Waveform( ...
    msg4Tx.Waveform*unitSpatialRow,cfg,ra,msg4Schedule,msg4Tx);
assert(controlDiversity.CausalGrantDecodeOk && ...
    isequal(msg4Diversity.TransportBlock,msg4Rx.TransportBlock) && ...
    isequaln(decodedDiversity,msg4Decoded));
localAssertStrict(msg4Tx.PDSCH,msg4Diversity,"msg4_contention_resolution");
localAssertReceiveDiversity(msg4Diversity);
assert(string(msg4Decoded.ContentionIdentity) ...
    == string(msg3.ContentionIdentity));
localAssertCommonReference(msg4Tx.PDSCH.IntegrationBinding,0,"msg4_contention_resolution");
localAssertCommonReference(msg4Rx.IntegrationBinding,0,"msg4_contention_resolution");
assert(string(msg4Tx.PDSCHControlEvent.Id) == ...
    string(msg4Rx.PDCCHControlEvent.Id), ...
    "Msg4 TX schedule and RX decode must bind to the same DCI event identity.");

badProcedure = localMsg2Context(cfg,ra,msg2Schedule);
badProcedure.RNTIType = "TC-RNTI";
localVerifyError(@() sixgr.pdsch.RASIPDSCHContext.materialize( ...
    msg2Tx.Carrier,msg2Schedule.PDSCH,struct(),badProcedure), ...
    "sixgr:pdsch:InvalidDCIRNTIProcedure");

badFields = localMsg2Context(cfg,ra,msg2Schedule);
badFields.MCSIndex = badFields.MCSIndex + 1;
localVerifyError(@() sixgr.pdsch.RASIPDSCHContext.materialize( ...
    msg2Tx.Carrier,msg2Schedule.PDSCH, ...
    msg2Tx.PDSCHControlEvent,badFields, ...
    "MaterializationRole","transmitter"), ...
    "sixgr:pdsch:ProcedureDCIFieldMismatch");

sibCfg = localSIBConfig();
sibTx = sixgr.phy.broadcast.generateSSB_MIB_SIB1_Waveform( ...
    sibCfg,"SNRdB",35,"Seed",1501);
sibRx = sixgr.phy.broadcast.recoverSIB1FromWaveform( ...
    sibTx.Waveform,sibCfg);
assert(logical(sibTx.PDSCHInfo.CanonicalDelegation));
assert(string(sibTx.PDSCHExecutionProfile) == "ra_si_strict");
assert(logical(sibRx.StrictOk) ...
    && logical(sibRx.PDSCHCanonicalDelegation));
localAssertCommonReference(sibTx.PDSCHTx.IntegrationBinding, ...
    sibTx.SSBInfo.SSBTiming.SelectedSSBIndex,"sib1");
assert(string(sibTx.PDSCHControlEvent.FieldProvenance.PRBSet) ...
    == "transmitter_scheduled_dci_payload_bits");
assert(string(sibTx.PDSCHControlEvent.FieldProvenance.DMRSConfiguration) ...
    == "validated_common_procedure_context");
localAssertSIBSpatialMapping(sibCfg);

ok = true;
end

function localAssertReceiveDiversity(rx)
assert(string(rx.ReceiverConfig.ChannelModel)=="AWGN");
assert(rx.ChannelEstimationMode=="dmrs_nr_channel_estimate_per_resource" && ...
    size(rx.OFDMGrid,3)==4 && size(rx.EffectiveLayerChannelEstimate,3)==4 && ...
    size(rx.EffectiveLayerChannelEstimate,4)==1);
assert(~rx.ChannelEstimationInfo.EstimatorUsesTrueChannel && ...
    isempty(rx.ChannelGainPerPhysicalPort));
end

function localAssertSIBSpatialMapping(cfg)
% Deterministic unit channel, not a measured spatial channel or beam sweep.
cfg.phy.ssb.Lmax=8;
cfg.phy.ssb.runtimeSSBIndex=0;
cfg.phy.ssb.activeBitmap="10000000";
cfg.phy.ssb.precoderMatrices=1;
cfg.phy.ssb.precoderIDs="component_fixture_identity";
cfg.phy.ssb.waveformDomain="physical_element_domain";
scalar=sixgr.phy.broadcast.generateSSB_MIB_SIB1_Waveform(cfg,'Seed',1502);
row=[1 1i -1 -1i]/2;
cfg.phy.ssb.precoderMatrices=row;
cfg.phy.ssb.precoderIDs="component_fixture_complex_four_elements";
physical=sixgr.phy.broadcast.generateSSB_MIB_SIB1_Waveform(cfg,'Seed',1502);
expected=scalar.SIB1Waveform*row;
assert(isequal(size(physical.SIB1Waveform),size(expected)));
assert(norm(physical.SIB1Waveform-expected,'fro')<1e-11*norm(expected,'fro'));
assert(norm(physical.Waveform-scalar.Waveform*row,'fro')<1e-11*norm(scalar.Waveform,'fro'));
assert(physical.SIB1SpatialMapping.MatrixAppliedHere);
assert(physical.SIB1SpatialMapping.PrecoderMatrixSHA256== ...
    physical.SSBBurstPlan.PrecoderMatrixSHA256(1));
% Apply an explicitly known unit-fixture channel for end-to-end decoding.
rx=sixgr.phy.broadcast.recoverSIB1FromWaveform(physical.Waveform*row',cfg);
assert(rx.StrictOk);
cfg.phy.ssb.waveformDomain="logical_rf_chain_post_analog_precoder";
logicalTx=sixgr.phy.broadcast.generateSSB_MIB_SIB1_Waveform(cfg,'Seed',1502);
assert(~logicalTx.SIB1SpatialMapping.MatrixAppliedHere);
assert(size(logicalTx.SIB1Waveform,2)==1);
assert(isequal(logicalTx.SIB1Waveform,scalar.SIB1Waveform));
assert(logicalTx.SIB1SpatialMapping.PhysicalProjectionOwner=="external_physical_projection_required");
end

function localAssertCommonReference(binding,index,procedure)
assert(isempty(fieldnames(binding.TCIState)));
ref=binding.ReceiverQCL;
assert(ref.SourceReferenceSignal=="SSB" && ref.SourceReferenceSignalId==index);
assert(ref.Procedure==procedure && ref.BindingKind=="common_procedure_reference");
assert(~ref.TCIActivationApplicable);
assert(ref.ReceiverParameterReuseStatus=="not_evaluated_by_reference_binding");
assert(binding.PrecoderBinding.Required && binding.PrecoderBinding.Status=="PASS");
assert(isnan(binding.PrecoderBinding.TCIStateId));
end

function localAssertStrict(tx,rx,procedure)
assert(logical(tx.CanonicalDelegation) ...
    && logical(rx.CanonicalDelegation));
assert(string(tx.ExecutionProfile) == "ra_si_strict" ...
    && string(rx.ExecutionProfile) == "ra_si_strict");
assert(tx.Assignment.Profile == "ra_si_strict" ...
    && rx.Assignment.Profile == "ra_si_strict");
assert(tx.Assignment.Source == "scheduled_dci+procedure_context" ...
    && rx.Assignment.Source == "decoded_dci+procedure_context");
assert(string(tx.IntegrationBinding.Status) == "PASS" ...
    && string(rx.IntegrationBinding.Status) == "PASS");
assert(logical(rx.Ok));
txEvent = tx.Assignment.toStruct();
rxEvent = rx.Assignment.toStruct();
assert(strlength(string(txEvent.ScheduledDCIId)) > 0 ...
    && strlength(string(txEvent.DecodedDCIId)) == 0 ...
    && string(txEvent.ControlAuthority) == "transmitter_scheduled_dci" ...
    && ~logical(txEvent.DCICRCPass));
assert(strlength(string(rxEvent.DecodedDCIId)) > 0 ...
    && strlength(string(rxEvent.ScheduledDCIId)) == 0 ...
    && string(rxEvent.ControlAuthority) == "receiver_crc_valid_decode" ...
    && logical(rxEvent.DCICRCPass));
assert(string(tx.Assignment.get("RNTIType")) == ...
    localRNTIType(procedure));
end

function type = localRNTIType(procedure)
switch string(procedure)
    case "msg2_rar"
        type = "RA-RNTI";
    case "msg4_contention_resolution"
        type = "TC-RNTI";
    otherwise
        type = "SI-RNTI";
end
end

function localAssertDataIndices(carrier,pdsch,plan)
sub = nrPDSCHIndices(carrier,pdsch, ...
    "IndexStyle","subscript","IndexBase","0based");
K = double(carrier.NSizeGrid)*12;
expected = unique(double(sub(:,1)+K*sub(:,2)),"sorted");
assert(isequal(sort(plan.DataIndices(:)),sort(expected(:))), ...
    "Strict RA/SI resource plan must equal the actual PDSCH data mapping.");
end

