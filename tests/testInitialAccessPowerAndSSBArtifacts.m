function ok = testInitialAccessPowerAndSSBArtifacts()
tmp = tempname;
mkdir(tmp);
c = onCleanup(@() localCleanupTempFolder(tmp)); %#ok<NASGU>

scenarioPath = fullfile("simulator", "configs", "scenarios", ...
    "lls_causal_access_to_data_wiring.yaml");
scfg = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scfg, fullfile(tmp, "run"));

sweepPath = fullfile(tmp, "ssb_pbch_sib1_beam_sweep.csv");
sweep = sixgr.link.runSSBBeamSweep(cfg, ...
    "MaxBeams", 4, ...
    "OutputPath", sweepPath);
assert(exist(sweepPath, "file") == 2, "SSB beam-sweep CSV must be written.");
assert(istable(sweep.TrialTable) && height(sweep.TrialTable) == 4, ...
    "Targeted SSB beam sweep must emit one row per swept beam.");
assert(isequal(sort(double(sweep.TrialTable.SSBIndex(:))).', 0:3), ...
    "SSB beam sweep must execute the requested SSB indices.");
assert(all(logical(sweep.TrialTable.SSBIndexMatch)), ...
    "Every successful targeted SSB trial must recover its requested SSB index.");
assert(all(ismember(["BCHCrcPass","MIBDecoded","SIB1StrictOk","TimingOffset_samples", ...
    "FrequencyOffsetHz","SSBReceivedPower_dB","SS_RSRP_dBm", ...
    "SS_RSRPPerReceiveAntenna_dBm","SS_RSRPRawObserved_dBm", ...
    "SS_RSRPRawObservedPerReceiveAntenna_dBm","SS_SINR_dB", ...
    "SS_SINRPerReceiveAntenna_dB","SSMeasurementSource", ...
    "SSSINRMeasurementMethod","SSSINRReferencePlane", ...
    "SSSINRNoiseInterferencePowerPerReceiveAntenna_W", ...
    "SSSINRDesiredPowerPerReceiveAntenna_W", ...
    "SSSINRNoiseInterferenceRECount", ...
    "ReferenceSignalTxEPRE_dBm","MeasuredReferenceSignalPathloss_dB", ...
    "PathlossReferenceRS", ...
    "SSPhysicalMeasurementStatus","PBCHDMRSMetric","PBCHNoiseVar", ...
    "StrictReceiverEvidenceOk","ReceiverHestSINR_dB","ChannelEstimateAvailable", ...
    "EqualizationAvailable","SIB1PDSCHStrictReceiverEvidenceOk","SIB1PDSCHReceiverHestSINR_dB", ...
    "PSSDetected","SSSDetected","NCellIDRecovered"], string(sweep.TrialTable.Properties.VariableNames))), ...
    "SSB beam-sweep artifact is missing acquisition metric columns.");
assert(all(logical(sweep.TrialTable.PSSDetected)) && ...
    all(logical(sweep.TrialTable.SSSDetected)) && ...
    all(logical(sweep.TrialTable.NCellIDRecovered)), ...
    "Every successful SSB receiver row must preserve explicit PSS, SSS, and cell-ID stage outcomes.");
assert(any(isfinite(double(sweep.TrialTable.SSBReceivedPower_dB))), ...
    "SSB beam sweep must export measured received SS/PBCH block power.");
assert(all(isfinite(double(sweep.TrialTable.SS_RSRP_dBm))) && ...
    all(isfinite(double(sweep.TrialTable.SS_SINR_dB))) && ...
    all(string(sweep.TrialTable.SSPhysicalMeasurementStatus) == ...
        "available_rsrp_and_sinr") && ...
    all(contains(string(sweep.TrialTable.SSMeasurementSource), ...
        "noise_debiased_linear_sss_re_power_and_received_reference_disturbance")) && ...
    all(contains(string(sweep.TrialTable.SSSINRMeasurementMethod), ...
        "same_ssb_bandwidth")) && ...
    all(double(sweep.TrialTable.SSSINRNoiseInterferenceRECount) > 0), ...
    char("Runtime initial-access rows must contain physical SS-RSRP and " + ...
        "resource-selective SS-SINR measured on the recovered SSS resources."));
assert(all(strlength(string(sweep.TrialTable.SS_RSRPPerReceiveAntenna_dBm)) > 0) && ...
    all(strlength(string(sweep.TrialTable.SS_SINRPerReceiveAntenna_dB)) > 0), ...
    "SS measurements must retain the per-receive-antenna evidence.");
assert(all(isfinite(double(sweep.TrialTable.ReferenceSignalTxEPRE_dBm))) && ...
    all(isfinite(double(sweep.TrialTable.MeasuredReferenceSignalPathloss_dB))) && ...
    all(startsWith(string(sweep.TrialTable.PathlossReferenceRS), "SSB-")) && ...
    all(double(sweep.TrialTable.SS_RSRPRawObserved_dBm) >= ...
        double(sweep.TrialTable.SS_RSRP_dBm)), ...
    ["Each runtime SSB row must retain exact generated Tx SSS EPRE, " ...
     "noise-debiased Rx SS-RSRP, and their identified pathloss."]);
assert(all(logical(sweep.TrialTable.SIB1StrictOk) & logical(sweep.TrialTable.StrictReceiverEvidenceOk)), ...
    "SSB/PBCH/SIB1 sweep rows must pass strict acquisition with measured receiver evidence.");
assert(all(isfinite(double(sweep.TrialTable.ReceiverHestSINR_dB))) && ...
    all(logical(sweep.TrialTable.ChannelEstimateAvailable)) && ...
    all(logical(sweep.TrialTable.EqualizationAvailable)), ...
    "SSB/PBCH/SIB1 sweep rows must export measured PBCH channel/equalization/SINR evidence.");
assert(all(logical(sweep.TrialTable.SIB1PDSCHStrictReceiverEvidenceOk)) && ...
    all(isfinite(double(sweep.TrialTable.SIB1PDSCHReceiverHestSINR_dB))), ...
    "SSB/PBCH/SIB1 sweep rows must export measured SI-RNTI PDSCH receiver evidence.");
assert(all(logical(sweep.TrialTable.RuntimeChannelStateUsed)) && ...
    sum(logical(sweep.TrialTable.SelectedBeamFlag)) == 1 && ...
    all(string(sweep.TrialTable.SelectionStatus) == ...
        "selected_from_successful_receiver_measurements"), ...
    "P1 SSB selection must use one successful runtime-channel receiver winner.");
assert(numel(unique(string(sweep.TrialTable.SSBBurstPrecoderMatrixSHA256))) == 4 && ...
    all(strlength(string(sweep.TrialTable.SSBBurstPrecoderMatrixSHA256)) == 64), ...
    "Each targeted SSB index must apply and export its own precoder matrix hash.");

% The coupled runtime transmits the complete configured SS burst set and
% measures each candidate occasion from that same composite waveform.  A
% one-hot stimulus alone cannot detect a receiver that repeatedly locks to
% the globally strongest candidate.  Exercise all four candidate-window
% requests against the unchanged four-beam burst and require the recovered
% PBCH/MIB index to follow the requested occasion exactly.
compositeRecovered = nan(1, 4);
for requestedSSBIndex = 0:3
    composite = sixgr.link.runCellSearch_MIB_SIB1(cfg, ...
        "NumSubframes", 5, ...
        "SSBIndex", requestedSSBIndex, ...
        "WriteArtifacts", false, ...
        "UseRuntimeChannel", false);
    compositeRecovered(requestedSSBIndex + 1) = double(composite.SSBIndex);
    assert(logical(composite.Ok) && logical(composite.PSSDetected) && ...
        logical(composite.SSSDetected) && logical(composite.NCellIDRecovered) && ...
        logical(sixgr.util.structGet(composite.PBCH, "Ok", false)), ...
        "Composite SS-burst candidate %d must complete the strict receiver chain.", ...
        requestedSSBIndex);
    assert(double(sixgr.util.structGet(composite.SSBTxEvidence, ...
        "ExecutedBeamCount", NaN)) == 4, ...
        "Composite candidate measurements must retain all four transmitted SSB beams.");
end
assert(isequal(compositeRecovered, 0:3), ...
    "Composite SS-burst candidate-window recovery must preserve SSB indices 0:3 exactly.");

derivedRunFolder = fullfile(tmp, "derived_run");
layout = sixgr.report.resultLayout(derivedRunFolder);
sixgr.util.ensureFolder(layout.BeamformingCSVDir);
sixgr.util.ensureFolder(layout.AirInterfaceCSVDir);
sixgr.util.csvWriteTable(fullfile(layout.AirInterfaceCSVDir, "pbch_trials.csv"), sweep.TrialTable);
beamPrecoderT = table( ...
    ["DL"; "DL"; "UL"], [1; 2; 1], [1; 2; 1], [1; 1; 1], [2; 2; 1], [2; 2; 1], ...
    'VariableNames', {'direction','selected_beam_index','best_beam_index','beam_hit', ...
    'precoding_num_ports','precoding_num_layers'});
sixgr.util.csvWriteTable(fullfile(layout.BeamformingCSVDir, "beam_precoder_table.csv"), beamPrecoderT);
rawTrials = struct("PBCH", sweep.TrialTable);
derived = sixgr.truth.exportLLSLiveDerivedTables(cfg, derivedRunFolder, rawTrials, struct(), struct(), struct());
beamStats = readtable(derived.BeamSelectionStatsPath, "TextType", "string");
assert(height(beamStats) > 0, "Live beam-selection stats must be populated from measured beam artifacts.");
assert(all(ismember(["BeamManagementProcedure","SignalSourceFamily"], string(beamStats.Properties.VariableNames))), ...
    "Combined live beam-selection stats must retain P1/P2 procedure provenance.");
assert(any(string(beamStats.Metric) == "P1SS_RSRP_dBm"), ...
    "Live beam-selection stats must include P1 noise-debiased SS-RSRP evidence.");
assert(any(string(beamStats.Metric) == "P2BeamHitRate"), ...
    "Live beam-selection stats must include P2/runtime selected-vs-best beam evidence.");
p1Stats = readtable(derived.BeamP1AcquisitionStatsPath, "TextType", "string");
p2Stats = readtable(derived.BeamP2RefinementStatsPath, "TextType", "string");
assert(height(p1Stats) > 0 && all(string(p1Stats.BeamManagementProcedure) == "P1_SSB_beam_sweep") && ...
    all(string(p1Stats.SignalSourceFamily) == "SSB_PBCH_SIB1"), ...
    "P1 acquisition stats must be emitted as clean SSB/PBCH/SIB1 beam-sweep evidence.");
assert(all(string(p1Stats.TraceSource) == "air_interface/csv/pbch_trials.csv") && ...
    any(string(p1Stats.Metric) == "P1PSSDetectionRate") && ...
    any(string(p1Stats.Metric) == "P1SSSDetectionRate") && ...
    any(string(p1Stats.Metric) == "P1SSBSweptBeamCount" & double(p1Stats.MeanValue) == 4), ...
    "P1 statistics must be sourced from all four same-scenario canonical PBCH receiver rows.");
assert(height(p2Stats) > 0 && all(startsWith(string(p2Stats.BeamManagementProcedure), "P2_runtime_beam")) && ...
    ~any(string(p2Stats.SignalSourceFamily) == "SSB_PBCH_SIB1"), ...
    "P2 refinement stats must not mix in P1 SSB/PBCH/SIB1 acquisition rows.");

sixgr.truth.exportLLSReportingBundle(derivedRunFolder, scfg, cfg, ...
    struct("Ok", true), struct("CodeVersion", "test", "CodeDetail", "test", ...
    "RandomSeed", 1, "GeneratedUTC", "test", "RunnerProfile", "test", ...
    "RunCompletion", "completed", "DeterministicMode", "test"), ...
    struct("StartedUTC", "test", "ElapsedSeconds", 1), struct());
beamMgmtOut = readtable(fullfile(layout.ReportCSVDir, "beam_management_outputs.csv"), ...
    "VariableNamingRule", "preserve", "TextType", "string");
beamIdentity = strcat(string(beamMgmtOut.CategoryKey), "|", ...
    string(beamMgmtOut.MetricKey), "|", string(beamMgmtOut.Entity), "|", ...
    string(beamMgmtOut.Statistic));
assert(numel(unique(beamIdentity)) == height(beamMgmtOut), ...
    "Beam-management rows must have unique category/metric/entity/statistic identities.");
baseTables = struct("ssb_pbch_table", sweep.TrialTable);
publicTables = sixgr.truth.buildLLSPublicOutputTables(baseTables, ...
    sixgr.truth.llsOutputContract(), struct( ...
    "logical_run_id", "ssb_four_beam_test", "run_id", 1));
ssbPublic = publicTables.ssb_pbch_cell_search_table;
assert(height(ssbPublic) == 4 && all(logical(ssbPublic.PSSDetected)) && ...
    all(logical(ssbPublic.SSSDetected)) && all(logical(ssbPublic.MIBRecovered)) && ...
    all(string(ssbPublic.PBCHCRC) == "pass") && ...
    isequal(sort(double(ssbPublic.SSBIndex(:))).', 0:3), ...
    "Public SSB/PBCH evidence must preserve all four measured beam rows and must not contradict successful PSS, SSS, PBCH, or MIB receiver stages.");
assert(any(string(beamMgmtOut.MetricKey) == "beam_detection_probability" & ...
    string(beamMgmtOut.Entity) == "ssb_p1_acquisition" & ...
    string(beamMgmtOut.Availability) == "observed" & ...
    contains(string(beamMgmtOut.SourceArtifact), "pbch_trials.csv") & ...
    contains(string(beamMgmtOut.Notes), "BeamManagementProcedure=P1_SSB_beam_sweep") & ...
    isfinite(double(beamMgmtOut.ValueNumeric))), ...
    "Canonical beam-management outputs must promote measured P1 SSB/PBCH detection evidence.");
assert(any(string(beamMgmtOut.MetricKey) == "beam_index_hit_rate" & ...
    string(beamMgmtOut.Entity) == "runtime_p2_beam_refinement" & ...
    string(beamMgmtOut.Availability) == "observed" & ...
    contains(string(beamMgmtOut.Notes), "BeamManagementProcedure=P2_runtime_beam_refinement") & ...
    isfinite(double(beamMgmtOut.ValueNumeric))), ...
    "Canonical beam-management outputs must promote measured P2 beam-refinement evidence separately from P1 acquisition.");
assert(any(string(beamMgmtOut.MetricKey) == "beam_management_overhead" & ...
    string(beamMgmtOut.Entity) == "ssb_p1_acquisition" & ...
    string(beamMgmtOut.Availability) == "observed" & ...
    double(beamMgmtOut.ValueNumeric) >= 2), ...
    "Canonical beam-management outputs must include measured SSB swept-beam overhead.");
assert(~any(string(beamMgmtOut.Availability) == "not_available"), ...
    "Primary beam-management outputs must not contain unmeasured placeholder rows.");

% The RA probe must consume both the runtime UE/cell antenna context and the
% receiver-selected P1 result.  This mirrors the coupled runtime state
% transition; passing the bare scenario would correctly fail because it has
% neither a physical serving-array binding nor a selected Msg2/Msg4 beam.
cfgRA = sixgr.config.normalizeConfig(cfg);
multiUser = struct("Enabled", true, "NumUsers", 1, "RNTIStart", 1, ...
    "ExecutionModel", "slot_coupled_truth");
state = sixgr.truth.CoupledTruthRuntime.initialize( ...
    cfgRA, fullfile(tmp, "ra_runtime"), multiUser, struct(), 1);
state.CurrentSlot = 2;
state.CurrentServingIdx(:) = 1;
[cfgRA, ~] = sixgr.truth.CoupledTruthRuntime.applyUserContext( ...
    cfgRA, state, 1, "UL");
cfgRA = sixgr.util.structSet(cfgRA, "phy.ssb.runtimeSSBIndex", ...
    double(sweep.SelectedSSBIndex));
cfgRA = sixgr.util.structSet(cfgRA, "random_access.associated_ssb_index", ...
    double(sweep.SelectedSSBIndex));
cfgRA = sixgr.util.structSet(cfgRA, ...
    "random_access.associated_ssb_selection_source", ...
    char(string(sweep.SelectionSource)));
cfgRA = sixgr.util.structSet(cfgRA, ...
    "random_access.associated_ssb_measurement_db", ...
    double(sweep.SelectionMetricValue_dB));

raFolder = fullfile(tmp, "ra");
res = sixgr.phy.ra.runFourStepRA(cfgRA, ...
    "RunFolder", raFolder, ...
    "RunId", "mobile_power_probe", ...
    "RuntimeIntegrationMode", "coupled_truth_runtime", ...
    "RequireRuntimeStageWaveforms", true, ...
    "AllowRuntimeStageWaveformComposition", true, ...
    "UseRuntimeChannel", true, ...
    "RuntimeNoiseSNR_dB", 20, ...
    "RuntimeSlot", 2, ...
    "WriteArtifacts", true);
assert(logical(res.StrictOk), "Mobile scenario four-step RA probe must complete.");

csvDir = fullfile(raFolder, "control", "csv");
attempts = readtable(fullfile(csvDir, "ra_attempts.csv"), "TextType", "string");
msg1 = readtable(fullfile(csvDir, "msg1_prach_detection.csv"), "TextType", "string");
msg2 = readtable(fullfile(csvDir, "msg2_rar_trials.csv"), "TextType", "string");
msg3 = readtable(fullfile(csvDir, "msg3_pusch_trials.csv"), "TextType", "string");
msg4 = readtable(fullfile(csvDir, "msg4_contention_resolution.csv"), "TextType", "string");

assert(isfinite(double(attempts.PowerPathloss_dB(1))), ...
    "RA power control must resolve finite scenario pathloss.");
assert(isfinite(double(msg1.PreambleTxPower_dBm(1))) && ...
    double(msg1.PreambleTxPower_dBm(1)) <= double(msg1.Pcmax_dBm(1)) + 1e-9, ...
    "PRACH transmit power must be computed and capped by Pcmax.");
assert(isfinite(double(msg3.Msg3TxPower_dBm(1))) && ...
    double(msg3.Msg3TxPower_dBm(1)) <= double(msg3.Pcmax_dBm(1)) + 1e-9, ...
    "Msg3 transmit power must be computed and capped by Pcmax.");
assert(isfinite(double(msg1.PreambleTxAmplitudeScale(1))) && ...
    isfinite(double(msg3.Msg3TxAmplitudeScale(1))), ...
    "Applied PRACH and Msg3 amplitude scales must be exported.");
assert(isfinite(double(attempts.DownlinkTxPower_dBm(1))) && ...
    isfinite(double(attempts.Msg2TxAmplitudeScale(1))) && ...
    isfinite(double(attempts.Msg4TxAmplitudeScale(1))), ...
    "RA Msg2/Msg4 downlink transmit power and amplitude scales must be exported.");
assert(isfinite(double(msg2.Msg2TxPower_dBm(1))) && ...
    isfinite(double(msg2.Msg2TxAmplitudeScale(1))) && double(msg2.Msg2TxAmplitudeScale(1)) > 1, ...
    "Msg2 RAR PDCCH/PDSCH waveform must be scaled by configured gNB downlink power.");
assert(isfinite(double(msg4.Msg4TxPower_dBm(1))) && ...
    isfinite(double(msg4.Msg4TxAmplitudeScale(1))) && double(msg4.Msg4TxAmplitudeScale(1)) > 1, ...
    "Msg4 contention-resolution PDCCH/PDSCH waveform must be scaled by configured gNB downlink power.");

ok = true;
end

function localCleanupTempFolder(pathIn)
if exist(pathIn, "dir") == 7
    try
        rmdir(pathIn, "s");
    catch
    end
end
end
