function ok = testMIMOFrequencySelectiveSpatialSignature()
%TESTMIMOFREQUENCYSELECTIVESPATIALSIGNATURE Preserve opposing subcarriers.

setup6GRSimToolkit("Verbose", false);
h = complex(zeros(2, 1, 2, 1));
h(1, 1, :, 1) = reshape([1; 1], 1, 1, 2, 1);
h(2, 1, :, 1) = reshape([1; -1], 1, 1, 2, 1);

wideband = sixgr.phy.mimo.spatialSignatureFromChannelEstimate( ...
    h, "Rank", 1, "SubspaceMode", "dominant_scheduled_rank");
assert(isequal(size(wideband), [2 1]), ...
    "Legacy wideband reduction should expose one averaged direction.");

[complete, info] = sixgr.phy.mimo.spatialSignatureFromChannelEstimate( ...
    h, "Rank", 1, "SubspaceMode", "complete_detectable_subspace", ...
    "NoiseVariance", 1e-8, "NoiseMargin_dB", 6);
assert(isequal(size(complete), [2 2]) && info.RetainedRank == 2 && ...
    info.RawNumericalRank == 2 && info.SnapshotCount == 2, ...
    ["The complete signature must retain both orthogonal frequency-selective " ...
     "directions that cancel under wideband averaging."]);
assert(string(info.ReductionMode) == "frequency_time_snapshot_covariance", ...
    "The exported reduction mode must identify snapshot-covariance evidence.");

localAssertTypedError(@()sixgr.phy.mimo.spatialSignatureFromChannelEstimate( ...
    h, "Rank", 1, "SubspaceMode", "complete_detectable_subspace", ...
    "NoiseMargin_dB", 6), "sixgr:mimo:MissingSpatialSignatureNoiseVariance");
localAssertTypedError(@()sixgr.phy.mimo.spatialSignatureFromChannelEstimate( ...
    h, "Rank", 1, "SubspaceMode", "complete_detectable_subspace", ...
    "NoiseVariance", 1e-8), "sixgr:mimo:MissingSpatialSignatureNoiseMargin");
ok = true;
end

function localAssertTypedError(fn, expectedId)
try
    fn();
catch ME
    assert(string(ME.identifier) == string(expectedId), ...
        "Expected %s, received %s.", expectedId, ME.identifier);
    return;
end
error("testMIMOFrequencySelectiveSpatialSignature:MissingError", ...
    "Expected typed error %s.", expectedId);
end
