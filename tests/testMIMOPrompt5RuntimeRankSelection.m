function H = localRank2Channel(nRx, nTx, seed)
rng(seed, "twister");
[U, ~] = qr(randn(nRx, 2) + 1i * randn(nRx, 2), 0);
[V, ~] = qr(randn(nTx, 2) + 1i * randn(nTx, 2), 0);
H = U * diag([4, 3]) * V';
end

