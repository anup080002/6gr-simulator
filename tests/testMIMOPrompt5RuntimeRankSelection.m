function ok = testMIMOPrompt5RuntimeRankSelection()
%TESTMIMOPROMPT5RUNTIMERANKSELECTION Prompt 5 rank-2 runtime evidence guard.

setup6GRSimToolkit("Verbose", false);

cfg = localCfg();
Hdl = localRank2Channel(4, 64, 1001);
decision = sixgr.mimo.resolveNominalVsEffectiveMIMO([], [], Hdl, 1e-3, 2, cfg.mimoRuntime);
assert(double(decision.EffectiveRank) == 2, "Measured well-conditioned 64x4 channel must select rank-2.");
assert(logical(decision.ExactMatch), "Runtime rank decision must match nominal rank-2.");
assert(size(decision.Precoder_W, 1) == 64 && size(decision.Precoder_W, 2) == 2, ...
    "Rank-2 DL decision must expose a 64-by-2 precoder.");
assert(double(decision.Rate_rank2_bps) > double(decision.Rate_rank1_bps), ...
    "Rank-2 rate must exceed rank-1 for the positive Prompt 5 channel.");

csi = sixgr.mimo.buildCSIFeedback(Hdl, 1e-3, cfg.mimoRuntime, "NominalRank", 2);
assert(double(csi.RI) == 2 && isfinite(double(csi.CQI)), ...
    "CSI feedback must carry runtime RI/CQI from measured channel.");

Hul = localRank2Channel(64, 4, 2002);
[Wul, beamIdx, ~, gainGap, ulInfo] = sixgr.mimo.selectULBeamFromSRS([], [], Hul, [], cfg.mimoRuntime);
assert(size(Wul, 1) == 4 && size(Wul, 2) == 2, ...
    "SRS-based UL selector must expose a 4-by-2 UE precoder.");
assert(isfinite(double(beamIdx)) && isfinite(double(gainGap)) && double(ulInfo.RI) == 2, ...
    "SRS-based UL selector must expose finite runtime beam evidence.");

raw = struct("DL", localRows("DL"), "UL", localRows("UL"));
out = sixgr.mimo.resolveNominalVsEffectiveMIMO(cfg.scenarioCfg, raw, ...
    "RunId", "prompt5", "ScenarioName", "rank2_mu_mimo", "StrictMode", true);
assert(all(logical(out.ConfiguredVsEffective.ScenarioObjectivePass)), ...
    "Prompt 5 runtime rows must clear configured-vs-effective MIMO objective.");
assert(all(double(out.ConfiguredVsEffective.ExactMatchPercent) >= 0.999), ...
    "Configured/effective exact-match fraction must be at least 99.9%.");
assert(all(logical(out.ConfiguredVsEffective.RuntimePopulated)), ...
    "Configured-vs-effective summary must be marked runtime populated.");
assert(all(double(out.ConfiguredVsEffective.RuntimeRank2Fraction) >= 0.999), ...
    "Runtime rank-2 fraction must be populated from trial rows.");
assert(all(logical(out.MIMOConfigStrict.RuntimePopulated)), ...
    "mimo_config_strict.csv payload must carry runtime trial population fields.");
assert(all(contains(string(out.MIMOConfigStrict.EvidenceClass), "RUNTIME")), ...
    "MIMO strict evidence class must no longer be configuration-only when runtime rows exist.");
assert(all(logical(out.AntennaArrayConfig.RuntimePopulated)) && ...
    all(~logical(out.AntennaArrayConfig.NominalCapabilityOnly)), ...
    "Antenna-array artifact must link to observed runtime trial rows.");

ok = true;
end

