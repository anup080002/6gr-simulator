function ok = testScheduledPTRSPortAssociation()
%TESTSCHEDULEDPTRSPORTASSOCIATION Verify config-driven frozen association.

setup6GRSimToolkit("Verbose", false);
cfg = sixgr.config.defaultConfig();
cfg.run.strictMode = true;
cfg.phy.pdsch.enablePTRS = true;
cfg.phy.ptrs.enable = true;
cfg.phy.pdsch.ptrs.portSet = 0;
cfg.phy.pdsch.ptrs.portAssociationPolicy = ...
    "first_scheduled_dmrs_port";

[enabled, ports, source] = ...
    sixgr.phy.grant.resolveScheduledPTRSPortSet( ...
    cfg, "DL", [2 3], struct("PTRSPortSet", 0));
assert(enabled && isequal(ports, 2) && ...
    string(source) == "yaml_policy_first_scheduled_dmrs_port", ...
    ["YAML policy must bind PT-RS to the first scheduled MU DM-RS port " ...
     "and must not be overridden by a stale grant alias."]);

cfg.phy.pdsch.ptrs.portAssociationPolicy = ...
    "configured_absolute_port";
threw = false;
try
    sixgr.phy.grant.resolveScheduledPTRSPortSet( ...
        cfg, "DL", [2 3], struct());
catch ME
    threw = string(ME.identifier) == ...
        "sixgr:phy:grant:PTRSPortNotInScheduledDMRS";
end
assert(threw, ...
    "An incompatible absolute YAML PT-RS port must fail loudly.");

cfg.phy.pdsch.enablePTRS = false;
[enabled, ports, source] = ...
    sixgr.phy.grant.resolveScheduledPTRSPortSet( ...
    cfg, "DL", [2 3], struct());
assert(~enabled && isempty(ports) && string(source) == ...
    "yaml_feature_disabled", ...
    "Disabled YAML PT-RS must remain disabled without a synthetic port.");
ok = true;
end
