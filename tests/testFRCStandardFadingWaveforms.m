function ok = testFRCStandardFadingWaveforms()
%TESTFRCSTANDARDFADINGWAVEFORMS Exercise exact DL/UL FRCs through TDL-B.

setup6GRSimToolkit("Verbose", false, "RunToolboxChecks", false);
cases = { ...
    "dl_r_pdsch_1_1_1_fdd_tdlb100_400", ...
        "tdlb100_400_ula_low_2x2", -0.8, "downlink"; ...
    "ul_g_fr1_a3_8_tdlb100_400", ...
        "tdlb100_400_low_1x2", -2.3, "uplink"};
for index = 1:size(cases,1)
    result = sixgr.conformance.runFRCPoint( ...
        cases{index,1}, cases{index,2}, "SNRGrid_dB", cases{index,3}, ...
        "ExecutionProfile", "smoke", "MinTransportBlocks", 1, ...
        "MaxTransportBlocks", 1, "BatchSize", 1, ...
        "EvaluateSymmetricRegression", false, ...
        "RequireExactStandardExecution", true, ...
        "RequireExactDataChannelExecution", true, ...
        "PrintTable", false, "Verbose", false);
    assert(result.StandardExecution.Exact && ...
        result.DataChannelExecution.Exact && ...
        result.Sweep.TransportBlocks == 1);
    detail = result.PointDetails{1};
    assert(string(detail.Propagation.Kind) == "fading" && ...
        string(detail.Propagation.Model) == "TDL-B" && ...
        detail.Propagation.FilterPad_samples > 0 && ...
        ~detail.ProxyUsed && ~detail.FallbackUsed);
    if string(cases{index,4}) == "downlink"
        wave = detail.Propagation.StandardDownlinkFrame;
    else
        wave = detail.Propagation.StandardUplinkWaveform;
    end
    assert(wave.Materialized && wave.NoProxyOrFallbackUsed && ...
        strlength(wave.FrameGridSHA256) == 64 && ...
        strlength(wave.FrameWaveformSHA256) == 64);
    assert(~result.StatisticallyQualified && ~result.NormativePass, ...
        "A one-TB fading implementation check must remain unqualified.");
end
ok = true;
end
