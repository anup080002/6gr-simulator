function ok = testQuickPlus20SameChainYAMLAuthority()
%TESTQUICKPLUS20SAMECHAINYAMLAUTHORITY Quick gate reduces scale, not features.

path = fullfile(pwd, "simulator", "configs", "scenarios", ...
    "webgui_sinr_plus20_64x4_mu_mimo_quick_truth.yaml");
s = sixgr.lls6g.config.loadScenarioConfig(path);

assert(double(s.get("canonical_control.run.total_slots")) == 32);
assert(isequal(double(s.get("canonical_control.run.seed_list")), 104729));
assert(isequal(double(s.get("canonical_control.run.fixed_link_snr_grid_db")), 20));
assert(~logical(s.get("sweeps_and_matrix.snr_sweep.enabled")));
assert(~logical(s.get("output.save_mat")) && ...
    ~logical(s.get("output.profiler_enabled")));
assert(logical(s.get("output.component_artifact_views.enabled")) && ...
    logical(s.get("output.component_artifact_views.required")));

enabledPaths = [ ...
    "canonical_control.initial_access.enabled", ...
    "canonical_control.reference_signals.ssb_enabled", ...
    "canonical_control.reference_signals.pbch_enabled", ...
    "canonical_control.reference_signals.csi_rs_enabled", ...
    "canonical_control.reference_signals.srs_enabled", ...
    "canonical_control.reference_signals.trs_enabled", ...
    "canonical_control.reference_signals.ptrs_enabled", ...
    "canonical_control.control.pdcch_enabled", ...
    "canonical_control.control.pucch_enabled", ...
    "canonical_control.mimo.mu_mimo_enable", ...
    "canonical_control.mimo.ul_mu_mimo_enable", ...
    "canonical_control.harq.enabled"];
for field = enabledPaths
    assert(logical(s.get(field)), "Quick truth gate disabled runtime feature %s.", field);
end

assert(~logical(s.get("canonical_control.random_access_evidence.false_alarm_test_enabled")));
assert(~logical(s.get("canonical_control.random_access_evidence.missed_detection_test_enabled")));
assert(~logical(s.get("canonical_control.random_access.statistical_qualification.enabled")));
assert(~logical(s.get("canonical_control.control.pdcch_strict.statistical_qualification.enabled")));
assert(logical(s.get("canonical_control.random_access_evidence.require_runtime_stage_waveforms")) && ...
    logical(s.get("canonical_control.random_access_evidence.allow_runtime_stage_waveform_composition")));

tmp = tempname();
mkdir(tmp);
cleanupTmp = onCleanup(@() localRemove(tmp)); %#ok<NASGU>
cfg = sixgr.lls6g.buildInternalConfig(s, tmp);
assert(double(cfg.run.numTTI) == 32 && ...
    double(cfg.channel.snr_dB) == 20 && ~logical(cfg.run.snrSweepEnabled), ...
    "Internal runtime scale is not the YAML +20 dB/32-slot authority.");
assert(~logical(cfg.run.useParallel) && double(cfg.run.numWorkers) == 1 && ...
    ~logical(cfg.run.autoStartParallelPool), ...
    "Quick gate must not start an unused process pool.");
assert(~logical(sixgr.util.structGet(cfg, ...
    "validation.random_access_evidence.false_alarm_test_enabled", true)) && ...
    ~logical(sixgr.util.structGet(cfg, ...
    "validation.random_access_evidence.missed_detection_test_enabled", true)), ...
    "Quick functional gate accidentally retained a separate PRACH statistical campaign.");
assert(~logical(sixgr.util.structGet(cfg, ...
    "phy.pdcch.operatorControl.pdcch_strict.statistical_qualification.enabled", true)), ...
    "Quick functional gate accidentally retained a separate PDCCH statistical campaign.");
assert(logical(sixgr.util.structGet(cfg, ...
    "validation.random_access_evidence.require_runtime_stage_waveforms", false)) && ...
    logical(sixgr.util.structGet(cfg, ...
    "validation.random_access_evidence.allow_runtime_stage_waveform_composition", false)), ...
    "Quick gate must require the YAML-authorized coupled RA stage waveforms.");
ok = true;
end

function localRemove(root)
if isfolder(root)
    rmdir(root, "s");
end
end
