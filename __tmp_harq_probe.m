baseScenario = fullfile(pwd, 'simulator', 'configs', 'scenarios', 'lls_100mhz_tdlc_bidirectional_truth.yaml');
candidates = [ ...
    6, 14; ...
    4, 14; ...
    2, 14; ...
    4, 18; ...
    2, 18; ...
    0, 18; ...
    -2, 18];
results = strings(0,1);
for i = 1:size(candidates,1)
    snr = candidates(i,1);
    mcs = candidates(i,2);
    tmp = tempname;
    mkdir(tmp);
    cleanupObj = onCleanup(@() rmdir(tmp, 's'));
    scenarioPath = fullfile(tmp, 'harq_probe.yaml');
    fid = fopen(scenarioPath, 'w');
    fprintf(fid, '%s', ['{' ...
        '"inherits":["' strrep(baseScenario, '\', '\\') '"],' ...
        '"meta":{"scenario_id":"harq_probe_' num2str(i) '","description":"harq probe","version":"1","owner":"test","maturity_tag":"smoke"},' ...
        '"simulation":{"n_frames":8,"n_slots":8,"monte_carlo_iterations":8,"snr_db":' num2str(snr) ',"snr_sweep_offsets_db":[-4,0]},' ...
        '"modulation":{"dl_mcs_index":' num2str(mcs) ',"ul_mcs_index":' num2str(mcs) '},' ...
        '"harq":{"enabled":true,"process_count":8,"rv_sequence":[0,2,3,1],"cbg_enabled":false,"feedback_timing_slots":4,"combining_mode":"soft","max_retx":3},' ...
        '"output":{"profile":"harq_probe_' num2str(i) '","save_figures":false,"save_mat":false}}']);
    fclose(fid);
    try
        out = run_6g_phy_lls_single(scenarioPath, 'results', 'probe');
        packetPath = fullfile(char(out.RunFolder), 'harq', 'csv', 'probe_harq_packets.csv');
        T = readtable(packetPath, 'VariableNamingRule', 'preserve');
        retxCount = sum(logical(T.IsRetransmission));
        ackRate = mean(double(T.ACK), 'omitnan');
        results(end+1) = sprintf('snr=%g mcs=%g -> retxRows=%d ackMean=%.3f', snr, mcs, retxCount, ackRate); %#ok<AGROW>
    catch ME
        results(end+1) = sprintf('snr=%g mcs=%g -> error: %s', snr, mcs, ME.message); %#ok<AGROW>
    end
    clear cleanupObj
end
for i = 1:numel(results)
    disp(results(i));
end
