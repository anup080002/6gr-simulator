setup6GRSimToolkit('Verbose',false);
p1 = sixgr.link.resolveMCSProfile('qam64_table1', 28);
assert(p1.Valid && p1.Qm == 6 && abs(p1.TargetCodeRate - 948/1024) < 1e-12);
p3 = sixgr.link.resolveMCSProfile('qam64lowse_table3', 28);
assert(p3.Valid && p3.Qm == 6 && abs(p3.TargetCodeRate - 772/1024) < 1e-12);
cfg = sixgr.config.defaultConfig();
cfg = sixgr.util.structSet(cfg, 'phy.csi.cqiTable', 'table1');
cfg = sixgr.util.structSet(cfg, 'phy.pdsch.mcsTable', 'qam64_table1');
cfg = sixgr.config.normalizeConfig(cfg);
[modStr, ~, mcs] = sixgr.link.amcFromCQI(15, '', NaN, cfg, 'DL');
assert(strcmpi(string(modStr), '64QAM'));
assert(double(mcs) == 28);
Hest = complex(reshape([1.00 1.05], [2 1 1 1]));
rxGrid = complex(reshape([1.00 0.90], [2 1 1 1]));
refInd = [1;2];
refSym = [1+0i;1+0i];
[csi, info] = sixgr.phy.dl.CSI_Feedback(Hest, 0.01, cfg, 'Direction', 'DL', 'ReceivedGrid', rxGrid, 'ReferenceIndices', refInd, 'ReferenceSymbols', refSym);
assert(isfield(csi, 'SINRSource'));
assert(isfield(info, 'MeasuredReferenceSINR_dB'));
disp(struct('mcs28',p1.TargetCodeRate,'table3_28',p3.TargetCodeRate,'cqi15mcs',mcs,'sinrSource',string(csi.SINRSource),'sinr',double(csi.SINR_dB)));
