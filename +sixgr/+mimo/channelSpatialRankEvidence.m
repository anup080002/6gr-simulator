function evidence = channelSpatialRankEvidence(H, rankTolerance)
% Separate simultaneous numerical rank from a multi-snapshot spatial span.
% H is explicitly Nrx-by-Ntx-by-Nsnapshot, including singleton dimensions.
% These are numerical channel-estimate diagnostics, NOT a decoded RI,
% noise-qualified physical rank, or a recommendation to schedule layers.
if nargin<2, rankTolerance=1e-8; end
assert(isnumeric(H) && ~isempty(H) && ndims(H)<=3 && ...
    all(isfinite(H(:))) && isnumeric(rankTolerance) && ...
    isscalar(rankTolerance) && isfinite(rankTolerance) && rankTolerance>0, ...
    'sixgr:mimo:InvalidSpatialRankInput', ...
    'Require finite RX-by-TX-by-snapshot estimates and a positive relative tolerance.');
H=double(H);
nRx=size(H,1); nTx=size(H,2); nSnapshots=size(H,3);
perSnapshot=zeros(nSnapshots,1);
for k=1:nSnapshots
    values=svd(H(:,:,k));
    perSnapshot(k)=sum(values>=max(values(1)*rankTolerance,eps));
end
% Preserve the established frequency-selective covariance calculation.
% Do not clamp this span to min(Nrx,Ntx): different REs can expose
% different directions without supporting those streams simultaneously.
[condition,status,span,values]=sixgr.mimo.channelConditionNumber( ...
    H,'RankTolerance',rankTolerance);
evidence=struct( ...
    'NumReceiveBranches',nRx,'NumTransmitPorts',nTx, ...
    'ChannelSnapshotCount',nSnapshots, ...
    'SimultaneousRankDimensionLimit',min(nRx,nTx), ...
    'NumericalRankPerSnapshot',perSnapshot, ...
    'MinimumSnapshotNumericalRank',min(perSnapshot), ...
    'MaximumSnapshotNumericalRank',max(perSnapshot), ...
    'AggregateSpatialSpanRank',span, ...
    'AggregateConditionNumber_dB',condition, ...
    'AggregateConditionNumberStatus',string(status), ...
    'AggregateSingularValues',values, ...
    'NumericalRankTolerance',rankTolerance, ...
    'RankSource',"received_channel_estimate_numerical_svd_not_RI", ...
    'NoiseQualifiedRank',false,'DecodedRI',false);
if nSnapshots>1
    evidence.AggregateDomain="transmit_snapshot_covariance";
else
    evidence.AggregateDomain="single_channel_matrix";
end
end
