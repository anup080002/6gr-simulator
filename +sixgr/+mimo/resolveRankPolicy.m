function policy = resolveRankPolicy(cfg)
%RESOLVERANKPOLICY One rank-policy authority for admission and adaptation.
% A fixed-rank alias must never become adaptive merely because it is not
% spelled "fixed". Preserve installed-runtime precedence and the reported
% token; this function does not select a rank, PMI, or received measurement.
token = lower(strtrim(string(sixgr.util.structGet(cfg, "runtime.link_adaptation.RankPolicy", ...
    sixgr.util.structGet(cfg, "phy.linkAdaptation.rankPolicy", ...
    sixgr.util.structGet(cfg, "phy.mimo.rankPolicy", ...
    sixgr.util.structGet(cfg, "mimo.rank_adaptation_policy", ...
    sixgr.util.structGet(cfg, "link_adaptation.rank_policy", "fixed"))))))));
assert(isscalar(token), 'sixgr:mimo:RankExecutionPolicy:BadPolicy', ...
    'Rank policy must be one scalar token.');
if token == "", token = "fixed"; end
token = replace(token, "-", "_");
fixed = ismember(token, ["fixed", "fixed_rank", "fixed_rank_anchor", ...
    "configured_fixed", "fixed_configured_rank", "anchor", "no_adaptation", ...
    "disabled", "none", "off", "false"]);
policy = struct('Policy', token, 'FixedRankAnchor', fixed, ...
    'AdaptiveRank', ~fixed);
end
