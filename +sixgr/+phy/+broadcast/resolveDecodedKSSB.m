function evidence=resolveDecodedKSSB(low4,additionalBits,Lmax,accepted)
% Original BCH operands, TS 38.212 V18.8.0 section 7.1.1.
% Lmax 4/8: additional bit extends MIB low four bits. Lmax 64: the
% three additional bits extend SSB index, NOT the subcarrier offset.
% This is semantic arithmetic, not proof that a receiver executed.
assert(isnumeric(Lmax)&&isreal(Lmax)&&isscalar(Lmax)&&any(Lmax==[4 8 64]), ...
    'sixgr:phy:broadcast:InvalidKSSBEvidence','Supported Lmax values are 4, 8 and 64.');
assert(islogical(accepted)&&isscalar(accepted), ...
    'sixgr:phy:broadcast:InvalidKSSBEvidence','Accepted must be scalar logical.');
evidence=struct('KSSBContractVersion',"sixgr_decoded_kssb/v2", ...
    'Lmax',double(Lmax),'MIBKSSBLow4',NaN,'PBCHKSSBMSB',NaN, ...
    'PBCHKSSBHighContribution',NaN,'KSSBHighBitApplicable',Lmax~=64, ...
    'DecodedKSSB',NaN,'MIBKSSBSubcarrierOffset',NaN);
if ~accepted,return;end
assert(isnumeric(low4)&&isreal(low4)&&isscalar(low4)&&isfinite(low4)&& ...
    low4==fix(low4)&&low4>=0&&low4<=15, ...
    'sixgr:phy:broadcast:InvalidKSSBEvidence','MIB low-four-bit value must be an integer 0..15.');
assert((isnumeric(additionalBits)||islogical(additionalBits))&&isreal(additionalBits)&& ...
    isvector(additionalBits)&&numel(additionalBits)==1+2*(Lmax==64)&& ...
    all(additionalBits(:)==0|additionalBits(:)==1), ...
    'sixgr:phy:broadcast:InvalidKSSBEvidence','Original BCH additional bits are missing or malformed.');
evidence.MIBKSSBLow4=double(low4);
if Lmax==64
    evidence.PBCHKSSBHighContribution=0; % arithmetic identity, not a decoded high bit
else
    evidence.PBCHKSSBMSB=double(additionalBits);
    evidence.PBCHKSSBHighContribution=16*evidence.PBCHKSSBMSB;
end
evidence.DecodedKSSB=evidence.MIBKSSBLow4+evidence.PBCHKSSBHighContribution;
evidence.MIBKSSBSubcarrierOffset=evidence.DecodedKSSB;
end
