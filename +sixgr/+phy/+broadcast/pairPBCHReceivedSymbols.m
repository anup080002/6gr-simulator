function evidence=pairPBCHReceivedSymbols(recovery,tx)
% Pair AFTER the receiver has finished. The actual transmitted logical grid
% supplies the reference, never detected decisions or re-encoded RX bits.
% PBCH's DM-RS channel estimate absorbs configured TX amplitude/beam gain;
% its equalized logical-symbol plane is unit QPSK, not connector RF power.
evidence=struct([]);
rx=sixgr.util.structGet(recovery,'PBCHEqualizedSymbols',[]);
indices=sixgr.util.structGet(recovery,'PBCHSymbolIndicesOneBased',[]);
ssb=double(sixgr.util.structGet(recovery,'SSBIndex',NaN));
grid=sixgr.util.structGet(tx,'SSBWaveInfo.ResourceGridSSBurst.ResourceGrid',[]);
plan=sixgr.util.structGet(tx,'SSBBurstPlan',struct());
if isempty(rx) || isempty(indices) || isempty(grid) || ~isfinite(ssb), return; end
assert(isscalar(ssb)&&ssb>=0&&ssb==fix(ssb), ...
    'sixgr:phy:broadcast:PBCHPairIdentity','Received SSB identity must be scalar.');
if ~ismember(ssb,double(plan.ActiveSSBIndices0Based)), return; end
first=double(plan.AbsoluteCandidateSymbols0Based(ssb+1))+1;
if first+3>size(grid,2), return; end
assert(size(grid,1)==240 && size(grid,3)==1 && ...
    isvector(rx) && numel(rx)==numel(indices), ...
    'sixgr:phy:broadcast:PBCHPairLayout','Pair exact logical PBCH REs, not physical antenna samples.');
reference=grid(:,first:first+3);
reference=reference(indices(:))/10^(double(plan.PerSSBPowerDB(ssb+1))/20);
assert(all(isfinite(reference)) && all(abs(abs(reference)-1)<1e-10) && ...
    all(isfinite(rx)) && all(indices>=1 & indices<=960), ...
    'sixgr:phy:broadcast:PBCHPairReference', ...
    'The retained producer grid and declared SSB power must yield actual unit QPSK reference symbols.');
evidence=struct('SignalName',"PBCH",'PortIndex',0, ...
    'PortRole',"equalized_logical_stream_not_physical_RX_antenna", ...
    'ObservationID',"received_SSB_"+string(ssb), ...
    'SampleIndex',double(indices(:)-1),'ReferenceReal',real(reference(:)), ...
    'ReferenceImag',imag(reference(:)),'MeasuredReal',real(rx(:)), ...
    'MeasuredImag',imag(rx(:)), ...
    'EVMDefinition',"reference_normalized_paired_symbol_evm", ...
    'AlignmentSource',"received_PSS_SSS_PBCH_DMRS_timing_frequency_and_MMSE_output", ...
    'ReferenceSource',"retained_transmitted_PBCH_logical_grid_declared_power_removed_after_reception", ...
    'MeasurementDomain',"equalized_resource_elements", ...
    'ReceiverUsesScoringReference',false,'GainOrPhaseFitted',false);
end
