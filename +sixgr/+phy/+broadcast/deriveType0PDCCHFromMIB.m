function [resolution, cfgSI] = deriveType0PDCCHFromMIB( ...
    carrier, cfg, mib, varargin)
%DERIVETYPE0PDCCHFROMMIB Compatibility façade for canonical Type-0 CSS.
%
% All normative table, monitoring, candidate and DCI-size decisions are
% owned by sixgr.phy.pdcch.Type0PDCCHResolver. YAML/config contributes the
% immutable carrier and procedure context only; decoded MIB bits always own
% controlResourceSetZero and searchSpaceZero.

p = inputParser;
p.addParameter("RNTI", 65535, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x));
p.addParameter("TimingOnly", false, ...
    @(x) islogical(x) && isscalar(x));
p.parse(varargin{:});
opt = p.Results;

if ~isstruct(mib)
    error("sixgr:phy:broadcast:InvalidMIB", ...
        "Decoded MIB evidence must be a scalar struct.");
end
pdcchConfigSIB1 = double(sixgr.util.structGet( ...
    mib, "PDCCHConfigSIB1", NaN));
if ~(isscalar(pdcchConfigSIB1) && isfinite(pdcchConfigSIB1) && ...
        pdcchConfigSIB1 >= 0 && pdcchConfigSIB1 <= 255 && ...
        pdcchConfigSIB1 == fix(pdcchConfigSIB1))
    error("sixgr:phy:broadcast:MIBPDCCHConfigMissing", ...
        "Decoded MIB does not contain a valid pdcch-ConfigSIB1 value.");
end
split = sixgr.phy.broadcast.splitPDCCHConfigSIB1( ...
    pdcchConfigSIB1, "Source", string(sixgr.util.structGet( ...
    mib, "Source", "decoded_mib")));

pdcchSCSKHz = double(localObjectOrStructField(carrier, ...
    "SubcarrierSpacing", sixgr.util.structGet(cfg, ...
    "phy.carrier.SubcarrierSpacing_kHz", NaN)));
ssbTiming = localResolveSSBTiming(cfg, pdcchSCSKHz);
if opt.TimingOnly
    resolution = struct( ...
        "TimingOnly", true, ...
        "MIB", split, ...
        "PDCCHConfigSIB1", double(split.PDCCHConfigSIB1), ...
        "CORESET0Index", double(split.CORESET0Index), ...
        "SearchSpaceZero", double(split.SearchSpaceZero), ...
        "SSBTiming", ssbTiming, ...
        "Status", ...
            "canonical_ssb_timing_resolved_before_type0_table_selection");
    cfgSI = cfg;
    return;
end

context = localType0Context( ...
    carrier, cfg, mib, split, ssbTiming, pdcchSCSKHz);
canonical = sixgr.phy.pdcch.Type0PDCCHResolver(context, ...
    "MonitoringFrameCount", localMonitoringFrameCount(cfg));
pdcch = localBuildPDCCH(carrier, canonical);

resolution = canonical;
resolution.PDCCH = pdcch;
resolution.MIB = split;
resolution.PDCCHConfigSIB1 = double(split.PDCCHConfigSIB1);
resolution.CORESET0Index = double(split.CORESET0Index);
resolution.SearchSpaceZero = double(split.SearchSpaceZero);
resolution.SSBTiming = ssbTiming;
resolution.Type0PDCCHCSS.RNTI = double(opt.RNTI);

cfgSI = localApplyType0ToConfig( ...
    cfg, canonical, pdcch, double(opt.RNTI), split, mib);
end

function context = localType0Context( ...
    carrier, cfg, mib, split, timing, pdcchSCSKHz)
nStartGrid = double(localObjectOrStructField( ...
    carrier, "NStartGrid", sixgr.util.structGet( ...
    cfg, "phy.carrier.NStartGrid", 0)));
nSizeGrid = double(localObjectOrStructField( ...
    carrier, "NSizeGrid", sixgr.util.structGet( ...
    cfg, "phy.carrier.NSizeGrid", NaN)));
initialStart = double(sixgr.util.structGet(cfg, ...
    "phy.bwp.dl.NStartBWP", sixgr.util.structGet(cfg, ...
    "phy.pdcch.nStartBWP", nStartGrid)));
initialSize = double(sixgr.util.structGet(cfg, ...
    "phy.bwp.dl.NSizeBWP", sixgr.util.structGet(cfg, ...
    "phy.pdcch.nSizeBWP", nSizeGrid)));
ssbSCSKHz = double(sixgr.util.structGet(timing, ...
    "SSBSubcarrierSpacingKHz", sixgr.util.structGet(cfg, ...
    "phy.ssb.scs_kHz", NaN)));
channelBandwidthMHz = localChannelBandwidthMHz( ...
    cfg, nSizeGrid, pdcchSCSKHz);
spectrumValue = sixgr.util.structGet(cfg, ...
    "initial_access.spectrum", sixgr.util.structGet(cfg, ...
    "lls6g.resolvedConfig.initial_access.spectrum", sixgr.util.structGet( ...
    cfg, "frequency.spectrum", "")));
spectrumToken = lower(strtrim(string(spectrumValue)));
sharedSpectrum = logical(sixgr.util.structGet(cfg, ...
    "initial_access.shared_spectrum", sixgr.util.structGet(cfg, ...
    "frequency.shared_spectrum", contains(spectrumToken, "shared"))));
kSSB = double(sixgr.util.structGet(mib, ...
    "SSBSubcarrierOffset", sixgr.util.structGet(cfg, ...
    "phy.ssb.KSSB", sixgr.util.structGet(timing, ...
    "GridRelationship.KSSB", 0))));

context = struct( ...
    "FrequencyRange", upper(strtrim(string(sixgr.util.structGet(cfg, ...
        "phy.frequencyRange", sixgr.util.structGet(cfg, ...
        "frequency.range_name", "FR1"))))), ...
    "SSBSCSKHz", ssbSCSKHz, ...
    "PDCCHSCSKHz", pdcchSCSKHz, ...
    "ChannelBandwidthMHz", channelBandwidthMHz, ...
    "SharedSpectrum", sharedSpectrum, ...
    "Note17Band", logical(sixgr.util.structGet(cfg, ...
        "initial_access.type0.note17_band", false)), ...
    "KSSB", kSSB, ...
    "CORESET0Index", double(split.CORESET0Index), ...
    "SearchSpaceZero", double(split.SearchSpaceZero), ...
    "SSBIndex", double(sixgr.util.structGet(mib, ...
        "SSBIndex", sixgr.util.structGet(cfg, ...
        "phy.ssb.runtimeSSBIndex", 0))), ...
    "SSBFrameNumber", double(sixgr.util.structGet(cfg, ...
        "phy.carrier.NFrame", 0)), ...
    "InitialDLBWPStart", initialStart, ...
    "InitialDLBWPSize", initialSize, ...
    "NCellID", double(localObjectOrStructField(carrier, ...
        "NCellID", sixgr.util.structGet(cfg, ...
        "phy.carrier.NCellID", 0))), ...
    "ConfigurationEpoch", double(sixgr.util.structGet(cfg, ...
        "initial_access.configuration_epoch", 1)));
end

function pdcch = localBuildPDCCH(carrier, canonical)
coreset = nrCORESETConfig;
try
    coreset.CORESETID = 0;
catch
    try
        coreset.ID = 0;
    catch
    end
end
coreset.Duration = double(canonical.CORESET0.DurationSymbols);
coreset.FrequencyResources = double( ...
    canonical.CORESET0.FrequencyResourceBitmap);
coreset.REGBundleSize = double(canonical.CORESET0.REGBundleSize);
coreset.InterleaverSize = double(canonical.CORESET0.InterleaverSize);
coreset.ShiftIndex = double(canonical.CORESET0.ShiftIndex);

searchSpace = nrSearchSpaceConfig;
searchSpace.SearchSpaceType = 'common';
try
    searchSpace.SearchSpaceID = 0;
catch
    try
        searchSpace.ID = 0;
    catch
    end
end
searchSpace.CORESETID = 0;
searchSpace.StartSymbolWithinSlot = double( ...
    canonical.SearchSpace0.StartSymbolWithinSlot);
searchSpace.SlotPeriodAndOffset = [ ...
    double(canonical.SearchSpace0.SlotPeriod), ...
    double(canonical.SearchSpace0.SlotOffset)];
searchSpace.Duration = double(canonical.SearchSpace0.DurationSlots);
searchSpace.NumCandidates = double( ...
    canonical.SearchSpace0.NumCandidates);

aggregationLevel = 4;
if canonical.SearchSpace0.NumCandidates(3) < 1
    aggregationLevel = 8;
end
pdcch = nrPDCCHConfig;
try
    pdcch.NCellID = double(carrier.NCellID);
catch
    try
        pdcch.DMRSScramblingID = double(carrier.NCellID);
    catch
    end
end
pdcch.RNTI = 0;
pdcch.CORESET = coreset;
pdcch.SearchSpace = searchSpace;
pdcch.AggregationLevel = aggregationLevel;
try
    % Type-0 CORESET offsets need not be aligned to six-RB bitmap groups.
    % Anchoring the PDCCH BWP at the resolved CORESET start preserves the
    % exact normative RB interval for the Toolbox resource generator.
    pdcch.NStartBWP = double(canonical.CORESET0.RBStart);
    pdcch.NSizeBWP = double(canonical.CORESET0.NumRB);
catch
end
end

function cfgSI = localApplyType0ToConfig( ...
    cfg, canonical, pdcch, rnti, split, mib)
cfgSI = cfg;
cfgSI = sixgr.util.structSet(cfgSI, "phy.pdcch.rnti", rnti);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.rntiType", "SI-RNTI");
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.scramblingRNTI", 0);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.dciFormat", "1_0");
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.dciPayloadBits", canonical.DCIPayloadBits);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.KBits", canonical.DCIPayloadBits);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.blindSearch", logical(sixgr.util.structGet( ...
    cfg, "phy.pdcch.blindSearch", false)));
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.allowBlindCandidateTimingEstimate", false);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.aggregationLevel", pdcch.AggregationLevel);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.aggregationLevels", ...
    canonical.SearchSpace0.AggregationLevels);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.searchSpace.numCandidates", ...
    canonical.SearchSpace0.NumCandidates);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.searchSpace.id", 0);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.searchSpace.startSymbol", ...
    canonical.SearchSpace0.StartSymbolWithinSlot);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.searchSpace.duration", ...
    canonical.SearchSpace0.DurationSlots);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.searchSpace.slotPeriodAndOffset", ...
    [canonical.SearchSpace0.SlotPeriod ...
    canonical.SearchSpace0.SlotOffset]);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.coreset.id", 0);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.coreset.duration", ...
    canonical.CORESET0.DurationSymbols);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.coreset.frequencyResources", ...
    canonical.CORESET0.FrequencyResourceBitmap);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.coreset.regBundleSize", ...
    canonical.CORESET0.REGBundleSize);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.coreset.interleaverSize", ...
    canonical.CORESET0.InterleaverSize);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.coreset.shiftIndex", ...
    canonical.CORESET0.ShiftIndex);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.nStartBWP", canonical.CORESET0.RBStart);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdcch.nSizeBWP", canonical.CORESET0.NumRB);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.sib1.decodedPDCCHConfigSIB1", ...
    double(split.PDCCHConfigSIB1));
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.sib1.coreset0Index", ...
    double(split.CORESET0Index));
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.sib1.searchSpaceZero", ...
    double(split.SearchSpaceZero));
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.sib1.pdcchConfigSIB1Source", ...
    char(string(split.Source)));
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.sib1.type0ResolutionSHA256", ...
    canonical.ResolutionSHA256);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.mib.dmrsTypeAPosition", double(sixgr.util.structGet( ...
    mib, "DMRSTypeAPosition", sixgr.util.structGet( ...
    cfgSI, "phy.mib.dmrsTypeAPosition", 2))));
cfgSI = sixgr.util.structSet(cfgSI, "phy.pdsch.RNTI", 65535);
cfgSI = sixgr.util.structSet(cfgSI, "phy.pdsch.rnti", 65535);
cfgSI = sixgr.util.structSet(cfgSI, ...
    "phy.pdsch.modulation", "QPSK");
cfgSI = sixgr.util.structSet(cfgSI, "phy.pdsch.numLayers", 1);
cfgSI = sixgr.util.structSet(cfgSI, "phy.pdsch.nLayers", 1);
cfgSI.phy.sib1.runtimePDCCH = pdcch;
end

function frameCount = localMonitoringFrameCount(cfg)
ordinal = double(sixgr.util.structGet(cfg, ...
    "initial_access.type0.monitoring_occasion_ordinal", ...
    sixgr.util.structGet(cfg, ...
    "phy.sib1.monitoringOccasionOrdinal", 1)));
if ~(isscalar(ordinal) && isfinite(ordinal) && ordinal >= 1 && ...
        ordinal == round(ordinal))
    error("sixgr:phy:broadcast:InvalidType0MonitoringOccasion", ...
        "monitoring_occasion_ordinal must be a positive integer.");
end
% Type-0 CSS occasions for this bounded FR1 profile repeat every two
% frames. Resolve enough frames to materialize the configured ordinal.
frameCount = max(2, 2 * ordinal);
end

function bandwidthMHz = localChannelBandwidthMHz(cfg, nRB, scsKHz)
bandwidthMHz = double(sixgr.util.structGet(cfg, ...
    "phy.channelBandwidth_MHz", NaN));
if ~isfinite(bandwidthMHz)
    bandwidthMHz = double(sixgr.util.structGet(cfg, ...
        "frequency.bandwidth_hz", NaN)) / 1e6;
end
if ~isfinite(bandwidthMHz)
    bandwidthMHz = double(sixgr.util.structGet(cfg, ...
        "phy.channelBandwidth_Hz", NaN)) / 1e6;
end
if ~isfinite(bandwidthMHz)
    bandwidthMHz = double(nRB) * 12 * double(scsKHz) / 1000;
end
end

function value = localObjectOrStructField( ...
    obj, fieldName, defaultValue)
value = defaultValue;
try
    if isobject(obj) && isprop(obj, fieldName)
        value = obj.(fieldName);
        return;
    end
    if isstruct(obj) && isfield(obj, fieldName)
        value = obj.(fieldName);
    end
catch
    value = defaultValue;
end
end

function timing = localResolveSSBTiming(cfg, carrierSCSKHz)
blockPattern = string(sixgr.util.structGet( ...
    cfg, "phy.ssb.blockPattern", "Case B"));
fcHz = double(sixgr.util.structGet(cfg, ...
    "phy.carrier.centerFrequency_Hz", ...
    sixgr.util.structGet(cfg, "frequency.center_frequency_hz", ...
    sixgr.util.structGet(cfg, "channel.fc_Hz", ...
    sixgr.util.structGet(cfg, "phy.fc_Hz", 3.5e9)))));
frequencyRange = string(sixgr.util.structGet(cfg, ...
    "phy.frequencyRange", ...
    sixgr.util.structGet(cfg, "frequency.range_name", "")));
timing = sixgr.phy.frame.SSBTimingResolver.resolve( ...
    "Case", blockPattern, ...
    "CarrierFrequencyHz", fcHz, ...
    "FrequencyRange", frequencyRange, ...
    "SSBSubcarrierSpacingKHz", sixgr.util.structGet( ...
        cfg, "phy.ssb.scs_kHz", NaN), ...
    "CarrierSubcarrierSpacingKHz", carrierSCSKHz, ...
    "Lmax", sixgr.util.structGet(cfg, "phy.ssb.Lmax", NaN), ...
    "PeriodicityMs", sixgr.util.structGet(cfg, ...
        "phy.ssb.periodicity_ms", ...
        sixgr.util.structGet(cfg, "phy.ssb.period_ms", 20)));
end
