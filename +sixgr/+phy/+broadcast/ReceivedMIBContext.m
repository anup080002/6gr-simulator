classdef (Sealed) ReceivedMIBContext
    %RECEIVEDMIBCONTEXT Compact immutable result of an original BCH receiver.
    % No TX payload, waveform, new reception, or network installation claim.
    % The public factory validates supplied original decoder operands; it is
    % not a cryptographic attestation of execution by an external caller.
    properties (SetAccess=private)
        Data (1,1) struct
        SHA256 (1,1) string
    end
    methods (Access=private)
        function obj=ReceivedMIBContext(data)
            obj.Data=data;
            obj.SHA256=localHash(data);
        end
    end
    methods (Static)
        function obj=fromDecodedBCH(pbch,received,capture,cfg,frameOrigin,frame,clock)
            assert(isstruct(pbch) && isscalar(pbch) && ...
                islogical(pbch.Ok) && isscalar(pbch.Ok) && pbch.Ok && pbch.ErrFlag==0 && ...
                islogical(pbch.BCHCRCValid) && isscalar(pbch.BCHCRCValid) && pbch.BCHCRCValid && ...
                islogical(pbch.CandidateIdentityConsistent) && isscalar(pbch.CandidateIdentityConsistent) && pbch.CandidateIdentityConsistent, ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Use original CRC-valid, identity-consistent PBCH output.');
            bits=pbch.TransportBlock;
            assert((isnumeric(bits)||islogical(bits)) && isreal(bits) && ...
                isvector(bits) && numel(bits)==24 && all(bits(:)==0|bits(:)==1), ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Original BCH transport block must contain exactly 24 binary bits.');
            for name=["BCHCrcPass","MIBDecoded","SSBIdentityVerified"]
                assert(isfield(received,name) && islogical(received.(name)) && ...
                    isscalar(received.(name)) && received.(name), ...
                    'sixgr:phy:broadcast:InvalidReceivedMIBContext','A verified original BCH/SSB identity is required.');
            end
            mib=sixgr.phy.broadcast.decodeMIBTransportBlock(bits);
            assert(string(received.MIBDecodedBitSource)=="nrBCHDecode" && ...
                string(received.BCHTransportBlockHex)==string(mib.TransportBlockHex) && ...
                string(received.BCHTransportBlockHash)==string(mib.TransportBlockHash), ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Decoded MIB bits must match the original BCH result.');
            kssb=sixgr.phy.broadcast.resolveDecodedKSSB( ...
                double(mib.SSBSubcarrierOffset),pbch.msbidxoffset,pbch.Lmax,true);
            for name=string(fieldnames(kssb)).'
                assert(isfield(pbch,name) && isequaln(pbch.(name),kssb.(name)), ...
                    'sixgr:phy:broadcast:InvalidReceivedMIBContext','Original decoded kSSB operands disagree with PBCH field %s.',name);
            end
            inner=pbch.DecodedMIBState;
            assert(isstruct(inner) && isscalar(inner) && ...
                string(inner.Source)=="crc_valid_nrBCHDecode_transport_block" && ...
                string(inner.BCHTransportBlockHash)==string(mib.TransportBlockHash) && ...
                string(inner.MIBSemanticSHA256)==string(mib.MIBSemanticSHA256) && ...
                isequal(inner.MIBInformationBits23,mib.MIBInformationBits23) && ...
                inner.NCellID==received.NCellID && inner.SSBIndex==received.MIBSSBIndex, ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Retain the original PBCH semantic state, not substituted configured MIB fields.');
            sfn=localInteger(received.MIBSystemFrameNumber,0,1023);
            lsb=localInteger(received.MIBSFN4LSBValue,0,15);
            lsbBits=pbch.SFN4LSB;
            assert((isnumeric(lsbBits)||islogical(lsbBits)) && isreal(lsbBits) && ...
                isvector(lsbBits) && numel(lsbBits)==4 && all(lsbBits(:)==0|lsbBits(:)==1) && ...
                sum(double(lsbBits(:)).*[8;4;2;1])==lsb && ...
                received.MIBKSSBSubcarrierOffset==kssb.DecodedKSSB, ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Original extra BCH payload and published receiver fields disagree.');
            pci=localInteger(received.NCellID,0,1007);
            ssb=localInteger(received.ObservedSSBOccasionIndex,0,63);
            half=localInteger(received.MIBHalfFrameBit,0,1);
            assert(islogical(received.StrictReceiverEvidenceOk) && isscalar(received.StrictReceiverEvidenceOk) && ...
                pbch.NCellID==pci && pbch.SSBIndex==ssb && pbch.HalfFrame==half, ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Original PBCH identity must match its measured SSB result.');
            frame=localInteger(frame,0,flintmax/160);
            assert(sfn==16*double(mib.SystemFrameNumberMSB6)+lsb && ...
                mod(frame,1024)==sfn && ssb==received.MIBSSBIndex, ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Original BCH frame and SSB fields disagree.');
            assert(isa(frameOrigin,'double') && isreal(frameOrigin) && isscalar(frameOrigin) && ...
                isfinite(frameOrigin) && frameOrigin==fix(frameOrigin) && abs(frameOrigin)<flintmax, ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Use the original measured capture-local frame origin.');
            fs=double(received.SampleRateHz);
            validateattributes(fs,{'double'},{'real','scalar','finite','positive'});
            count=localInteger(received.SIB1AvailableCaptureSamples,1,flintmax);
            bound=isa(capture,'sixgr.phy.waveform.WaveformObservationBuffer');
            if bound
                assert(isscalar(capture) && capture.isComplete() && capture.SampleRateHz==fs, ...
                    'sixgr:phy:broadcast:InvalidReceivedMIBContext','Original capture must be complete on the receiver sample clock.');
                first=localInteger(capture.StartSample,0,flintmax);
                stop=localInteger(capture.EndSampleExclusive,first+1,flintmax);
                digest=capture.sampleHash(); columns=capture.NumReceiveAntennas;
                frameSamples=fs/100;
                assert(stop-first==count && frameSamples==fix(frameSamples) && ...
                    abs(first+frameOrigin)<flintmax && ...
                    round((first+frameOrigin)/frameSamples)==frame, ...
                    'sixgr:phy:broadcast:InvalidReceivedMIBContext','Capture epoch and measured frame origin disagree.');
            else
                validateattributes(capture,{'single','double'},{'2d','nonempty','finite'});
                assert(size(capture,1)==count, ...
                    'sixgr:phy:broadcast:InvalidReceivedMIBContext','Original array extent and receiver extent disagree.');
                first=NaN; stop=NaN; columns=size(capture,2);
                digest=sixgr.phy.waveform.WaveformHash.runtimeArray(capture);
            end
            cfo=received.FrequencyOffsetHz;
            phaseOrigin=received.CFOCorrectionSampleOrigin;
            assert(isnumeric(cfo) && isreal(cfo) && isscalar(cfo) && isfinite(cfo) && ...
                isnumeric(phaseOrigin) && isreal(phaseOrigin) && isscalar(phaseOrigin) && ...
                isfinite(phaseOrigin) && phaseOrigin==fix(phaseOrigin) && phaseOrigin>=0 && phaseOrigin<count, ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Original CFO estimate and phase origin must be finite.');
            mib.SSBIndex=ssb; mib.SystemFrameNumber=sfn;
            % Semantic inner state retains its original four MIB bits. The
            % Type-0 input uses the actual assembled BCH/MIB value instead.
            mib.SSBSubcarrierOffset=kssb.DecodedKSSB;
            if bound, mib.AbsoluteFrameNumber=frame; end
            geometry=sixgr.phy.broadcast.ReceivedMIBContext.receiverGeometry(cfg);
            assert(geometry.Lmax==pbch.Lmax && double(inner.ConfigurationEpoch)==geometry.ConfigurationEpoch, ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Original receiver domain/configuration epoch changed.');
            data=struct('ContractVersion',"sixgr.received_mib_context/v1", ...
                'Source',"original_received_SSB_identity_and_CRC_valid_nrBCHDecode", ...
                'TransportBlockBits',int8(bits(:)), 'MIB',mib, ...
                'OriginalDecodedMIBState',inner,'DecodedKSSBEvidence',kssb, ...
                'OriginalBCHAdditionalBits',int8(pbch.msbidxoffset(:)), ...
                'OriginalBCHSFN4LSBBits',int8(pbch.SFN4LSB(:)), ...
                'NCellID',pci,'SSBIndex',ssb,'HalfFrame',half,'ReceivedSFN',sfn, ...
                'AbsoluteFrameNumber',frame,'GlobalCaptureEpochBound',bound, ...
                'CaptureStartSample',first,'CaptureEndSampleExclusive',stop, ...
                'AvailableAtSample',stop,'CaptureSampleSHA256',string(digest), ...
                'CaptureSampleCount',count, ...
                'NumReceiveAntennas',double(columns),'SampleRateHz',fs, ...
                'FrameOriginInOriginalCapture_samples',frameOrigin, ...
                'ReceivedFrameOriginSample',first+frameOrigin,'RadioFrameClock',string(clock), ...
                'FrequencyOffsetHz',double(cfo), ...
                'CFOPhaseOriginInOriginalCapture_samples',double(phaseOrigin), ...
                'CFOPhaseOriginSample',first+double(phaseOrigin), ...
                'CFOEstimateSource',string(received.CFOCorrectionSource), ...
                'ReceiverGeometry',geometry, ...
                'OriginalStrictReceiverEvidenceOk',logical(received.StrictReceiverEvidenceOk), ...
                'AvailabilityBasis',"original_completed_capture_end_not_runtime_delivery_latency", ...
                'NewBCHReception',false,'NetworkConfigurationInstalled',false);
            obj=sixgr.phy.broadcast.ReceivedMIBContext(data);
        end

        function geometry=receiverGeometry(cfg)
            c=sixgr.phy.grid.makeCarrier(cfg);
            t=sixgr.phy.frame.SSBTimingResolver.resolveFromConfig(cfg);
            candidates=double(t.CandidateStartSymbolsWithinHalfFrame(:).');
            assert(numel(candidates)==double(t.Lmax) && all(isfinite(candidates)) && ...
                all(candidates>=0 & candidates==fix(candidates)) && all(diff(candidates)>0), ...
                'sixgr:phy:broadcast:InvalidReceivedSSBGeometry', ...
                'Retain the complete ordered original SSB candidate-symbol geometry.');
            geometry=struct('NSizeGrid',double(c.NSizeGrid),'NStartGrid',double(c.NStartGrid), ...
                'SubcarrierSpacing',double(c.SubcarrierSpacing),'CyclicPrefix',string(c.CyclicPrefix), ...
                'SSBSCSKHz',double(t.SSBSubcarrierSpacingKHz), ...
                'FrequencyRange',string(t.FrequencyRange),'Lmax',double(t.Lmax), ...
                'SSBCase',string(t.Case),'SSBCyclicPrefix',"normal", ...
                'SSBCandidateStartSymbolsWithinHalfFrame',candidates, ...
                'SSBLowOffsetFromPointAHz',double(t.GridRelationship.SSBLowOffsetFromPointAHz), ...
                'ConfigurationEpoch',sixgr.util.structGet(cfg,'initial_access.configuration_epoch',1));
            % Freeze original tuning/table inputs, not mutable frame/slot,
            % TX payload, selected TX occasion, or later decoded DCI fields.
            paths=["phy.frequencyRange","frequency.range_name", ...
                "phy.carrier.centerFrequency_Hz","frequency.center_frequency_hz", ...
                "channel.fc_Hz","phy.fc_Hz","frequency.band_name","initial_access.band_context", ...
                "phy.channelBandwidth_MHz","frequency.bandwidth_hz","phy.channelBandwidth_Hz", ...
                "initial_access.spectrum","frequency.spectrum","initial_access.shared_spectrum", ...
                "frequency.shared_spectrum","initial_access.type0.note17_band", ...
                "phy.bwp.dl.NStartBWP","phy.bwp.dl.NSizeBWP", ...
                "phy.pdcch.nStartBWP","phy.pdcch.nSizeBWP"];
            inputs=cell(numel(paths),1);
            for k=1:numel(paths)
                inputs{k}=sixgr.util.structGet(cfg,paths(k),struct('OriginalPathAbsent',true));
            end
            geometry.OriginalTuningInputPaths=paths;
            geometry.OriginalTuningInputValues=inputs;
        end

        function cfg=normalizeReceiverConfig(cfg,rnti)
            if ~isfield(cfg,'phy'), cfg.phy=struct(); end
            if ~isfield(cfg.phy,'carrier'), cfg.phy.carrier=struct(); end
            cfg.phy.carrier.NCellID=double(sixgr.util.structGet(cfg,'phy.carrier.NCellID',1));
            cfg.phy.carrier.SubcarrierSpacing=double(sixgr.util.structGet(cfg,'phy.carrier.SubcarrierSpacing', ...
                sixgr.util.structGet(cfg,'phy.carrier.SubcarrierSpacing_kHz',30)));
            cfg.phy.carrier.SubcarrierSpacing_kHz=cfg.phy.carrier.SubcarrierSpacing;
            cfg.phy.carrier.NSizeGrid=double(sixgr.util.structGet(cfg,'phy.carrier.NSizeGrid',52));
            cfg.phy.carrier.NStartGrid=double(sixgr.util.structGet(cfg,'phy.carrier.NStartGrid',0));
            cfg.phy.carrier.NSlot=0; cfg.phy.carrier.NFrame=0;
            cfg.phy.pdcch.rnti=double(rnti); cfg.phy.pdcch.scramblingRNTI=0;
            cfg.phy.pdcch.blindSearch=logical(sixgr.util.structGet(cfg,'phy.pdcch.blindSearch',false));
            sixgr.config.assertRuntimeFeatureUse(cfg,'pdcch_blind_search',cfg.phy.pdcch.blindSearch,'recoverSIB1FromWaveform');
            cfg.phy.pdcch.allowBlindCandidateTimingEstimate=false;
            cfg.phy.pdcch.searchSpace.numCandidates=[0 0 1 0 0];
        end
    end
    methods
        function validate(obj,cfg)
            assert(isscalar(obj) && localHash(obj.Data)==obj.SHA256, ...
                'sixgr:phy:broadcast:InvalidReceivedMIBContext','Original received context digest changed.');
            assert(isequaln(obj.Data.ReceiverGeometry, ...
                sixgr.phy.broadcast.ReceivedMIBContext.receiverGeometry(cfg)), ...
                'sixgr:phy:broadcast:ReceivedMIBGeometryChanged','Retained MIB requires its original tuned receiver geometry and configuration epoch.');
            pci=sixgr.util.structGet(cfg,'phy.carrier.NCellID',NaN);
            assert(isnumeric(pci) && isscalar(pci) && pci==obj.Data.NCellID, ...
                'sixgr:phy:broadcast:ReceivedMIBCellMismatch','SI receiver cell must match the original received PCI.');
        end
    end
end

function value=localInteger(value,low,high)
assert(isa(value,'double') && isreal(value) && isscalar(value) && ...
    isfinite(value) && value>=low && value<=high && value==fix(value), ...
    'sixgr:phy:broadcast:InvalidReceivedMIBContext','Clock and identity fields must be exact scalar doubles.');
end

function digest=localHash(data)
digest=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(data))));
end
