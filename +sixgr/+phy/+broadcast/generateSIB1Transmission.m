function localValidateAssociation(cfg,carrier,info)
% Validate the retained mapping before any native channel encoder executes.
required={'NCellID','NSizeGrid','NStartGrid','SubcarrierSpacing_kHz', ...
    'SampleRate_Hz','SSBTiming','SSBBurstPlan','SSB','WaveformDomain'};
assert(all(isfield(info,required)), ...
    'sixgr:phy:broadcast:InvalidSIB1Association','Original SSB association fields are missing.');
for name=["NCellID","NSizeGrid","NStartGrid"]
    localEqualNumber(info.(name),double(carrier.(name)),name);
end
localEqualNumber(info.SubcarrierSpacing_kHz,double(carrier.SubcarrierSpacing),"carrier SCS");
sampling=sixgr.phy.frame.OFDMSamplingResolver.resolve(carrier);
localEqualNumber(info.SampleRate_Hz,double(sampling.SampleRateHz),"sample rate");
assert(isstruct(info.SSB) && isscalar(info.SSB) && ...
    all(isfield(info.SSB,{'PDCCHConfigSIB1','DMRSTypeAPosition'})) && ...
    isstruct(info.SSBTiming) && isscalar(info.SSBTiming) && ...
    all(isfield(info.SSBTiming,{'SelectedSSBIndex','Case', ...
    'SSBSubcarrierSpacingKHz','CarrierSubcarrierSpacingKHz','GridRelationship'})), ...
    'sixgr:phy:broadcast:InvalidSIB1Association','Retain original MIB and SSB timing identity.');
localEqualNumber(info.SSB.PDCCHConfigSIB1,localPDCCHConfigSIB1(cfg),"pdcch-ConfigSIB1");
localEqualNumber(info.SSB.DMRSTypeAPosition, ...
    sixgr.util.structGet(cfg,'phy.mib.dmrsTypeAPosition',2),"dmrs-TypeA-Position");
index=info.SSBTiming.SelectedSSBIndex;
assert(isnumeric(index) && isreal(index) && isscalar(index) && isfinite(index) && ...
    index>=0 && index==fix(index), ...
    'sixgr:phy:broadcast:InvalidSIB1Association','Selected SSB index must be an original numeric integer.');
configured=sixgr.phy.broadcast.resolveSIB1TransmitSSBIndices(cfg);
assert(ismember(index,configured), ...
    'sixgr:phy:broadcast:SIB1AssociationMismatch','The retained selected SSB is not a configured SI association.');
expected=sixgr.phy.frame.SSBTimingResolver.resolveFromConfig(cfg,'SSBIndex',index);
localEqualNumber(info.SSBTiming.SSBSubcarrierSpacingKHz,expected.SSBSubcarrierSpacingKHz,"SSB SCS");
localEqualNumber(info.SSBTiming.CarrierSubcarrierSpacingKHz,expected.CarrierSubcarrierSpacingKHz,"SSB carrier SCS");
assert(isequaln(info.SSBTiming.GridRelationship,expected.GridRelationship) && ...
    isequal(string(info.SSBTiming.Case),string(expected.Case)), ...
    'sixgr:phy:broadcast:SIB1AssociationMismatch','The original SSB frequency geometry must match SI configuration.');
plan=info.SSBBurstPlan;
assert(isstruct(plan) && isscalar(plan) && ...
    all(isfield(plan,{'PrecoderMatrices','PrecoderMatrixSHA256','NumTransmitAntennas','ActiveBitmap'})) && ...
    iscell(plan.PrecoderMatrices) && numel(plan.PrecoderMatrices)>index && ...
    islogical(plan.ActiveBitmap) && numel(plan.ActiveBitmap)>index && plan.ActiveBitmap(index+1) && ...
    numel(plan.PrecoderMatrixSHA256)>index, ...
    'sixgr:phy:broadcast:InvalidSIB1Association','SI requires an active original SSB and retained precoder.');
row=plan.PrecoderMatrices{index+1};
assert(isnumeric(row) && isrow(row) && ~isempty(row) && all(isfinite(row)) && ...
    abs(norm(row)-1)<=1e-9 && isnumeric(plan.NumTransmitAntennas) && ...
    isscalar(plan.NumTransmitAntennas) && isreal(plan.NumTransmitAntennas) && ...
    plan.NumTransmitAntennas==numel(row), ...
    'sixgr:phy:broadcast:InvalidSIB1SpatialMapping','Original SSB precoder dimensions/normalization disagree.');
digest=sixgr.util.sha256Hex(jsonencode(struct('Size',size(row), ...
    'Real',real(double(row)),'Imag',imag(double(row)))));
assert(isequal(string(plan.PrecoderMatrixSHA256(index+1)),string(digest)), ...
    'sixgr:phy:broadcast:SIB1AssociationMismatch','Original selected SSB precoder hash is inconsistent.');
assert((ischar(info.WaveformDomain) && isrow(info.WaveformDomain)) || ...
    (isstring(info.WaveformDomain) && isscalar(info.WaveformDomain)), ...
    'sixgr:phy:broadcast:InvalidSIB1Association','Retain one waveform-domain token.');
assert(any(string(info.WaveformDomain)==["physical_element_domain", ...
    "logical_rf_chain_post_analog_precoder"]), ...
    'sixgr:phy:broadcast:InvalidSIB1SpatialMapping','Unknown original SSB waveform domain.');
end

function localEqualNumber(actual,expected,label)
assert(isnumeric(actual) && isreal(actual) && isscalar(actual) && isfinite(actual) && ...
    isnumeric(expected) && isreal(expected) && isscalar(expected) && isfinite(expected) && ...
    actual==expected, ...
    'sixgr:phy:broadcast:SIB1AssociationMismatch','Original SSB %s disagrees with SI configuration.',label);
end
