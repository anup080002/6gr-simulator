function definition=resolveExperimentalMCSTable(name)
% Explicit catalog-only lab codepoints. Unknown names have no definition.
definition=[];
name=lower(strtrim(string(name)));
if ~isscalar(name) || ~startsWith(name,"experimental_"), return; end
catalog=sixgr.lls6g.config.loadParameterCatalog('scenario');
tables=catalog.value_maps.experimental_mcs_tables;
if iscell(tables)
    tableNames=string(cellfun(@(row)char(string(row.name)),tables,'UniformOutput',false));
else
    tableNames=string({tables.name});
end
hit=find(tableNames==name);
if isempty(hit), return; end
assert(isscalar(hit),'sixgr:research:InvalidMCSTable','Experimental table names must be unique.');
if iscell(tables), t=tables{hit}; else, t=tables(hit); end
indices=double(t.indices(:)); qm=double(t.qm(:));
if isfield(t,'rates_x1024')
    assert(~isfield(t,'code_rates'), ...
        'sixgr:research:InvalidMCSTable', ...
        'Specify either exact rates_x1024 or code_rates, not both.');
    ratesX1024=double(t.rates_x1024(:));
    rates=ratesX1024/1024;
else
    rates=double(t.code_rates(:));
    ratesX1024=rates*1024;
end
width=5;
if isfield(t,'index_width_bits'), width=double(t.index_width_bits); end
reservedIndices=zeros(0,1); reservedQm=zeros(0,1);
if isfield(t,'reserved_indices'), reservedIndices=double(t.reserved_indices(:)); end
if isfield(t,'reserved_qm'), reservedQm=double(t.reserved_qm(:)); end
allIndices=[indices;reservedIndices];
directQmBits=0; directSelectorBits=0;
if isfield(t,'direct_qm_field_bits')
    directQmBits=double(t.direct_qm_field_bits);
    directSelectorBits=double(t.direct_selector_bits);
end
assert(string(t.research_class)=="optional_research_experiment" && ...
    ~isempty(indices) && numel(indices)==numel(qm) && numel(indices)==numel(rates) && ...
    isscalar(width) && ismember(width,[5 6 7]) && ...
    numel(reservedIndices)==numel(reservedQm) && ...
    numel(unique(allIndices))==numel(allIndices) && ...
    all(isfinite(allIndices) & allIndices==fix(allIndices) & ...
        allIndices>=0 & allIndices<2^width) && ...
    all(ismember(qm,[2 4 6 8 10])) && all(ismember(reservedQm,[2 4 6 8 10])) && ...
    all(isfinite(rates) & rates>0 & rates<1) && ...
    all(isfinite(ratesX1024) & ratesX1024>0 & ratesX1024<1024), ...
    'sixgr:research:InvalidMCSTable', ...
    'Install unique in-width regular/stored-TBS indices, square QAM and finite regular code rates in (0,1).');
if directQmBits>0
    assert(directQmBits==3 && directSelectorBits==4 && width==7 && ...
        all(floor(indices/16)==localQmCodes(qm)) && ...
        all(mod(indices,16)<15) && ...
        all(floor(reservedIndices/16)==localQmCodes(reservedQm)) && ...
        all(mod(reservedIndices,16)==15), ...
        'sixgr:research:InvalidDirectMCSMap', ...
        'Direct C5 requires Qm code in three high bits and a four-bit rate/stored-TBS selector.');
else
    assert(width~=7,'sixgr:research:InvalidDirectMCSMap', ...
        'A seven-bit experimental table must declare its direct field split.');
end
definition=struct('Name',name,'ResearchClass',string(t.research_class), ...
    'StandardNR',false,'IndexWidthBits',width, ...
    'Rows',[indices qm rates],'ReservedRows',[reservedIndices reservedQm], ...
    'RatesX1024',ratesX1024,'DirectQmFieldBits',directQmBits, ...
    'DirectSelectorBits',directSelectorBits);
end

function codes=localQmCodes(qm)
order=[2 4 6 8 10];
[present,position]=ismember(qm,order);
assert(all(present),'sixgr:research:InvalidDirectMCSMap', ...
    'Direct Qm code requires one of the five declared modulation orders.');
codes=position-1;
end
