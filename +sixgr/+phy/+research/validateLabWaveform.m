function profiles=validateLabWaveform(s)
%VALIDATELABWAVEFORM Explicit, bounded clean-IQ / DMRS-AWGN lab contract.
sixgr.lls6g.config.validateScenarioConfig(s);
assert(isfield(s,'lab_waveform'),'sixgr:lab:MissingPolicy','lab_waveform is required.');
p=s.lab_waveform;
assert(string(s.scenario.runner_profile)=="lab_waveform_campaign" && ...
    string(s.meta.research_class)=="optional_research_experiment", ...
    'sixgr:lab:Scope','Select the explicitly classified lab waveform campaign.');
disabled=["initial_access.enabled","random_access.enabled","control.pdcch_enabled", ...
    "control.pucch_enabled","control.blind_search_enabled","harq.enabled", ...
    "users.enabled","ai_ml.enabled","mimo.beam_sweep_enabled", ...
    "reference_signals.ssb_enabled","reference_signals.pbch_enabled", ...
    "reference_signals.csi_rs_enabled","reference_signals.srs_enabled", ...
    "reference_signals.trs_enabled","reference_signals.tracking_rs_enabled", ...
    "reference_signals.ptrs_enabled","reference_signals.csi_reporting_enabled", ...
    "reference_signals.cqi_reporting_enabled","reference_signals.pmi_reporting_enabled", ...
    "reference_signals.ri_reporting_enabled","impairments.cfo_enabled", ...
    "impairments.phase_noise_enabled","impairments.iq_imbalance_enabled", ...
    "impairments.pa_nonlinearity_enabled","impairments.timing_offset_enabled"];
for field=disabled
    assert(~logical(sixgr.util.structGet(s,field,true)), ...
        'sixgr:lab:EnabledUnsupportedBlock','%s must be explicitly disabled.',field);
end
assert(s.frequency.carrier_count==1 && ~s.frequency.carrier_aggregation_enabled && ...
    string(s.frequency.duplex_mode)=="TDD" && string(s.channels.model_type)=="AWGN" && ...
    string(s.channels.profile)=="AWGN" && s.channels.doppler_hz==0 && ...
    ~s.channels.pathloss_enabled && ~s.channels.shadow_fading_enabled && ...
    string(s.research_link.channel)=="identity_awgn" && ...
    string(s.research_link.noise_reference)=="unit_constellation_per_port_after_precoding" && ...
    string(s.research_link.timing)=="preconfigured_slot_boundary" && ...
    string(s.research_link.rf)=="ideal_no_impairments", ...
    'sixgr:lab:ChannelPolicy','Lab campaign requires single-carrier TDD, configured timing and identity AWGN only.');
assert(~isfield(s,'research_adaptation') && ~isfield(s,'research_spatial') && ...
    ~isfield(s,'research_awgn_mimo'),'sixgr:lab:UnsupportedOverride', ...
    'Lab campaign does not accept adaptation, physical-array or alternate power overrides.');
assert(string(s.research_receiver.channel_estimation)=="dmrs" && ...
    string(s.research_receiver.noise_estimation)=="received_dmrs", ...
    'sixgr:lab:ReceiverPolicy','Instrument reference uses received DMRS estimation, not perfect CSI.');
assert(s.waveform.explicit_sample_rate_hz==s.waveform.explicit_fft_size*s.frame.scs_khz*1e3 && ...
    s.waveform.windowing_samples==0,'sixgr:lab:NativeOFDM','Require native Fs=Nfft*SCS and zero windowing.');
assert(numel(unique(p.dl_mcs_indices))==numel(p.dl_mcs_indices) && ...
    numel(unique(p.rx_snr_db))==numel(p.rx_snr_db) && ...
    ~isempty(p.dl_mcs_indices) && ~isempty(p.rx_snr_db), ...
    'sixgr:lab:DuplicateCases','MCS and SNR lists must be nonempty and unique.');
assert(~isempty(regexp(p.output_group,'^[A-Za-z0-9_-]+$','once')), ...
    'sixgr:lab:OutputGroup','output_group must be a simple directory name.');
assert(exist('nrPDSCHMCSTables','file')==2,'sixgr:lab:ToolboxVersion', ...
    'This profile requires nrPDSCHMCSTables (R2024a or later); no guessed MCS fallback.');
m=nrPDSCHMCSTables; table4=m.QAM1024Table;
profiles=struct('MCS',{},'Qm',{},'TargetCodeRate',{});
for k=1:numel(p.dl_mcs_indices)
    row=table4(table4.MCSIndex==p.dl_mcs_indices(k),:);
    assert(height(row)==1 && row.Qm==10 && isfinite(row.TargetCodeRate), ...
        'sixgr:lab:MCSAuthority','Configured DL MCS must be a defined 1024-QAM table entry.');
    profiles(k)=struct('MCS',double(row.MCSIndex),'Qm',double(row.Qm), ...
        'TargetCodeRate',double(row.TargetCodeRate)); %#ok<AGROW>
end
assert(s.research_dl.target_code_rate==profiles(1).TargetCodeRate, ...
    'sixgr:lab:MCSRateMismatch','research_dl.target_code_rate must match the primary DL MCS lookup.');
for direction=["dl","ul"]
    c=s.("research_"+direction);
    assert(c.enabled && string(c.modulation)=="1024QAM" && ~c.transform_precoding && ...
        ~c.uci_enabled && ~c.harq_enabled && c.rv==0 && ...
        c.num_layers==s.mimo.n_layers && c.num_layers==s.mimo.n_tx_ant && ...
        c.num_layers==s.mimo.n_rx_ant && c.prb_start==0 && ...
        c.num_prbs==s.frequency.n_size_grid && isequal(double(c.symbol_allocation(:)'),[0 14]), ...
        'sixgr:lab:AllocationPolicy','Require full-slot/full-band equal-port/layer 1024-QAM without HARQ/UCI.');
end
end
