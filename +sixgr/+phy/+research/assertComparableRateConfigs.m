function assertComparableRateConfigs(configs)
%ASSERTCOMPARABLERATECONFIGS Fail before execution if link budgets differ.
assert(numel(configs)>=2,'sixgr:research:InsufficientCandidates','Configure at least two rate candidates.');
signatures=cell(size(configs)); ids=strings(size(configs));
for k=1:numel(configs)
    s=configs{k}.toStruct(); ids(k)=configs{k}.ScenarioID;
    assert(string(s.scenario.runner_profile)=="research_tdd_link" && ...
        string(s.meta.research_class)=="optional_research_experiment", ...
        'sixgr:research:WrongCandidateProfile','All candidates must be explicit research TDD links.');
    assert(~s.research_link.require_all_tb_success, ...
        'sixgr:research:ExplorationPolicyRequired', ...
        'Candidate sweeps must retain negative TB results without aborting comparison.');
    % Compare every live PHY/noise/timing policy, not only the headline SNR.
    signature=struct('frequency',s.frequency,'frame',s.frame,'waveform',s.waveform, ...
        'simulation',s.simulation,'channels',s.channels,'impairments',s.impairments, ...
        'research_link',s.research_link, ...
        'research_dl',rmfield(s.research_dl,'target_code_rate'), ...
        'research_ul',rmfield(s.research_ul,'target_code_rate'));
    signatures{k}=signature;
    if k>1
        assert(isequaln(signatures{1},signature),'sixgr:research:IncomparableRateCandidates', ...
            'Only DL/UL target code rates may differ; carrier, noise, power, timing, layers and sampling must match.');
    end
end
assert(numel(unique(ids))==numel(ids),'sixgr:research:DuplicateCandidateID','Candidate IDs must be unique.');
end
