classdef MeasurementValidityChecker
    %MEASUREMENTVALIDITYCHECKER Complete-key and finite-age validation.

    methods (Static)
        function result = validate(measurement,consumer)
            measuredRequired = ["MeasurementID","UEID","CellID","BWPID", ...
                "ResourceID","BeamID","ConfigurationEpoch","ProducerSlot", ...
                "AvailableSlot"];
            for field = measuredRequired
                if ~isfield(measurement,char(field)) || ...
                        (field=="MeasurementID" && ...
                        (ismissing(string(measurement.MeasurementID)) || ...
                        strlength(string(measurement.MeasurementID))==0))
                    error("RSLA:MissingMeasuredInput", ...
                        "Measured state is missing required field %s.",field);
                end
            end
            required = ["UEID","CellID","BWPID","ResourceID","BeamID", ...
                "ConfigurationEpoch","ConsumerSlot","MaxAgeSlots"];
            for field = required
                if ~isfield(consumer,char(field))
                    error("RSLA:WrongMeasurementIdentity", ...
                        "Consumer identity is missing %s.",field);
                end
            end
            maxAge = double(consumer.MaxAgeSlots);
            if ~(isscalar(maxAge)&&isfinite(maxAge)&&maxAge>=0)
                error("RSLA:StaleMeasurement", ...
                    "Strict consumers require a finite nonnegative MaxAgeSlots.");
            end
            age = double(consumer.ConsumerSlot)-double(measurement.ProducerSlot);
            identity = double(measurement.UEID)==double(consumer.UEID) && ...
                double(measurement.CellID)==double(consumer.CellID) && ...
                double(measurement.BWPID)==double(consumer.BWPID) && ...
                string(measurement.ResourceID)==string(consumer.ResourceID) && ...
                string(measurement.BeamID)==string(consumer.BeamID) && ...
                double(measurement.ConfigurationEpoch)== ...
                    double(consumer.ConfigurationEpoch);
            available = double(measurement.AvailableSlot)<= ...
                double(consumer.ConsumerSlot);
            fresh = age>=0 && age<=maxAge;
            if ~identity
                error("RSLA:WrongMeasurementIdentity", ...
                    "Measurement identity does not match the requesting consumer.");
            end
            if ~available || ~fresh
                error("RSLA:StaleMeasurement", ...
                    "Measurement age/availability violates the finite consumer policy.");
            end
            result = struct("Valid",true,"IdentityValid",identity, ...
                "Available",available,"AgeSlots",age, ...
                "MaxAgeSlots",maxAge);
        end
    end
end
