classdef SRSResourceEngine
    %SRSRESOURCEENGINE Exact strict SRS resource/resource-set façade.

    methods (Static)
        function plan = planVector(row)
            ports = sixgr.phy.rsla.RSLAUtil.number(row,"Ports",NaN);
            resourceType = lower(sixgr.phy.rsla.RSLAUtil.text( ...
                row,"ResourceType",""));
            usage = lower(sixgr.phy.rsla.RSLAUtil.text(row,"Usage",""));
            comb = sixgr.phy.rsla.RSLAUtil.number(row,"TransmissionComb",NaN);
            combOffset = sixgr.phy.rsla.RSLAUtil.number(row,"CombOffset",NaN);
            cyclicShift = sixgr.phy.rsla.RSLAUtil.number(row,"CyclicShift",NaN);
            startPosition = sixgr.phy.rsla.RSLAUtil.number( ...
                row,"StartPosition",NaN);
            nSymbols = sixgr.phy.rsla.RSLAUtil.number( ...
                row,"NumberOfSymbols",NaN);
            cSRS = sixgr.phy.rsla.RSLAUtil.number(row,"C_SRS",NaN);
            bSRS = sixgr.phy.rsla.RSLAUtil.number(row,"B_SRS",NaN);
            bHop = sixgr.phy.rsla.RSLAUtil.number(row,"B_Hop",NaN);
            hopping = lower(sixgr.phy.rsla.RSLAUtil.text( ...
                row,"HoppingMode",""));
            sequenceID = sixgr.phy.rsla.RSLAUtil.number(row,"SequenceID",NaN);
            trigger = sixgr.phy.rsla.RSLAUtil.number(row,"TriggerState",NaN);
            maxShift = 8*double(comb==2)+12*double(comb==4);
            valid = ismember(ports,[1 2 4]) && ...
                ismember(resourceType,["periodic","semipersistent","aperiodic"]) && ...
                ismember(usage,["beammanagement","codebook","noncodebook"]) && ...
                ismember(comb,[2 4]) && ...
                isfinite(combOffset) && combOffset>=0 && combOffset<comb && ...
                isfinite(cyclicShift) && cyclicShift>=0 && cyclicShift<maxShift && ...
                ismember(startPosition,0:5) && ismember(nSymbols,[1 2 4]) && ...
                startPosition+nSymbols<=6 && ...
                isfinite(cSRS) && cSRS>=0 && cSRS<=63 && ...
                ismember(bSRS,0:3) && ismember(bHop,0:3) && ...
                ismember(hopping,["none","interresource","intraresource","interslot"]) && ...
                isfinite(sequenceID) && sequenceID>=0 && sequenceID<=1023 && ...
                isfinite(trigger) && trigger>=0 && trigger<=3 && ...
                ~(usage=="beammanagement" && ports>1 && nSymbols==2);
            if ~valid
                error("RSLA:InvalidSRSConfiguration", ...
                    "Invalid SRS tuple for the bounded Release-18 profile.");
            end
            srs = nrSRSConfig;
            try
                srs.NumSRSPorts = ports;
                srs.SymbolStart = 13-startPosition-(nSymbols-1);
                srs.NumSRSSymbols = nSymbols;
                srs.Repetition = 1;
                srs.KTC = comb;
                srs.KBarTC = combOffset;
                srs.CyclicShift = cyclicShift;
                srs.NSRSID = sequenceID;
                srs.GroupSeqHopping = "neither";
                srs.FrequencyStart = 0;
                srs.CSRS = cSRS;
                srs.BSRS = bSRS;
                srs.BHop = bHop;
                switch resourceType
                    case "periodic"
                        srs.ResourceType = "periodic";
                        srs.SRSPeriod = [20 0];
                    case "semipersistent"
                        srs.ResourceType = "semi-persistent";
                        srs.SRSPeriod = [20 0];
                otherwise
                        srs.ResourceType = "aperiodic";
                end
                carrier = nrCarrierConfig("NSizeGrid",max(52,double(srs.NRB)), ...
                    "SubcarrierSpacing",30,"NCellID",1,"NSlot",0);
                indices = nrSRSIndices(carrier,srs,"IndexBase","0based");
                symbols = nrSRS(carrier,srs);
            catch cause
                wrapped = MException("RSLA:InvalidSRSConfiguration", ...
                    "Toolbox rejected the exact SRS tuple: %s.",cause.message);
                wrapped = addCause(wrapped,cause);
                throw(wrapped);
            end
            plan = struct("Ports",ports,"ResourceType",resourceType, ...
                "Usage",usage,"TransmissionComb",comb, ...
                "CyclicShift",cyclicShift,"HoppingMode",hopping, ...
                "IndicesZeroBased",double(indices(:)),"Symbols",symbols(:), ...
                "IndexSHA256",sixgr.phy.rsla.RSLAUtil.hash(double(indices(:))), ...
                "SequenceSHA256",sixgr.phy.rsla.RSLAUtil.hash( ...
                    [real(symbols(:)) imag(symbols(:))]), ...
                "ConfigurationEpoch",1, ...
                "ExecutionBackend","matlab_5g_toolbox_waveform_kernel", ...
                "ApproximationMode","none");
        end
    end
end
