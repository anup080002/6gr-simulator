classdef DecodedCSIReportEvent
    %DECODEDCSIREPORTEVENT Scheduler-authoritative decoded report event.

    properties (SetAccess=immutable)
        Data struct
    end

    methods
        function obj = DecodedCSIReportEvent(decoded,report,availableSlot)
            if ~decoded.CRCValid || ~decoded.SemanticValid
                error("RSLA:CSIReportDecodeFailure", ...
                    "Only CRC-valid and semantically valid CSI may create an event.");
            end
            obj.Data = struct("EventID","DECODED-"+report.ReportID, ...
                "ReportID",report.ReportID,"Fields",decoded.Fields, ...
                "ConfigurationEpoch",decoded.ConfigurationEpoch, ...
                "UEID",report.MeasurementIdentity.UEID, ...
                "CellID",report.MeasurementIdentity.CellID, ...
                "BWPID",report.MeasurementIdentity.BWPID, ...
                "ResourceID",report.MeasurementIdentity.ResourceID, ...
                "ProducerSlot",report.ProducerSlot, ...
                "AvailableSlot",double(availableSlot), ...
                "Source","decoded_csi_report_event", ...
                "Valid",true);
        end
    end
end
