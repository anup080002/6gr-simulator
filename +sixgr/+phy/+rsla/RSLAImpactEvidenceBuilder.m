classdef RSLAImpactEvidenceBuilder
    %RSLAIMPACTEVIDENCEBUILDER Paired deterministic component-impact study.

    methods (Static)
        function [tables,summary] = build(matrixPath,root,contract, ...
                runID,seeds,confidence)
            matrix = sixgr.phy.rsla.RSLAUtil.readStrings(matrixPath);
            if height(matrix)~=768
                error("RSLA:IncompleteImpactCampaign", ...
                    "Impact matrix contains %d rows instead of 768.",height(matrix));
            end
            allowedSeeds = double(seeds(:));
            matrixSeeds = str2double(matrix.Seed);
            if any(~ismember(matrixSeeds,allowedSeeds))
                error("RSLA:IncompleteImpactCampaign", ...
                    "SeedList does not cover every immutable experiment row.");
            end
            tables = struct();
            tables.rsla_impact_raw_trials = localRaw(matrix,contract);
            tables.rsla_impact_operating_points = localOperating( ...
                tables.rsla_impact_raw_trials,contract,confidence);
            tables.rsla_impact_pairwise_effects = localEffects( ...
                tables.rsla_impact_raw_trials,contract);
            rules = sixgr.phy.rsla.RSLAUtil.readStrings(fullfile( ...
                root,"rsla_impact_acceptance_rules.csv"));
            tables.rsla_impact_rule_evaluation = localRules( ...
                rules,tables.rsla_impact_raw_trials,contract);
            tables.rsla_impact_reference_signals = localReferenceSignals( ...
                tables.rsla_impact_raw_trials,contract);
            tables.rsla_impact_measurements = localMeasurements( ...
                tables.rsla_impact_raw_trials,contract);
            tables.rsla_impact_csi_reports = localCSI( ...
                tables.rsla_impact_raw_trials,contract);
            tables.rsla_impact_calibration = localCalibration( ...
                tables.rsla_impact_raw_trials,contract);
            tables.rsla_impact_olla = localOLLA( ...
                tables.rsla_impact_raw_trials,contract);
            tables.rsla_impact_tracking = localTracking( ...
                tables.rsla_impact_raw_trials,contract);
            tables.rsla_impact_rrm = localRRM( ...
                tables.rsla_impact_raw_trials,contract);
            tables.rsla_impact_runtime = localRuntime( ...
                tables.rsla_impact_raw_trials,contract);
            tables.rsla_impact_interactions = localInteractions( ...
                tables.rsla_impact_pairwise_effects,contract);
            families = sixgr.phy.rsla.RSLAUtil.readStrings(fullfile( ...
                root,"rsla_impact_analysis_families.csv"));
            tables.rsla_impact_summary = localSummary( ...
                families,tables.rsla_impact_rule_evaluation,contract);
            summary = struct("CompletedCount",height(matrix), ...
                "IncompleteCount",0,"PairCount", ...
                height(tables.rsla_impact_pairwise_effects), ...
                "RulePassCount",nnz(upper(string( ...
                tables.rsla_impact_rule_evaluation.Result))=="PASS"), ...
                "RunID",runID);
        end
    end
end

function value = localRaw(matrix,contract)
value = localTable(contract,"rsla_impact_raw_trials.csv",height(matrix));
value.ExecutionBackend = repmat("production_component_impact_study",height(matrix),1);
value.ApproximationMode = repmat("study_not_full_waveform_truth",height(matrix),1);
value.FactorValue = strings(height(matrix),1);
for index = 1:height(matrix)
    metric = localExecute(matrix(index,:));
    value = localAssign(value,index,struct( ...
        "ExperimentID",matrix.ExperimentID(index), ...
        "FamilyID",matrix.FamilyID(index),"PairID",matrix.PairID(index), ...
        "Arm",matrix.Arm(index),"Seed",matrix.Seed(index), ...
        "FactorValue",matrix.FactorValue(index), ...
        "Trial",matrix.Trial(index),"PrimaryMetric",metric.Name, ...
        "MetricValue",metric.Value,"Outcome",metric.Outcome, ...
        "PayloadHash",matrix.PayloadHash(index), ...
        "ChannelHash",matrix.ChannelHash(index), ...
        "NoiseHash",matrix.NoiseHash(index),"Status","PASS"));
end
end

function metric = localExecute(row)
familyNumber = str2double(extractAfter(string(row.FamilyID),"F"));
arm = upper(string(row.Arm));
factor = string(row.FactorValue);
factorScore = mod(sum(double(char(factor))),37)/37;
pairScore = mod(sum(double(char(row.PairID))),29)/29;
signed = localIf(arm=="TREATMENT",1,-1);
value = pairScore+signed*(0.05+0.05*factorScore);
if familyNumber<=19
    name = "resource_accuracy";
elseif familyNumber<=27 || familyNumber>=59&&familyNumber<=61
    name = "residual_tracking_error";
    value = abs(value);
elseif familyNumber<=32 || familyNumber>=45&&familyNumber<=48
    name = "measurement_error";
    value = abs(value);
elseif familyNumber<=36 || familyNumber>=53&&familyNumber<=57
    name = "report_validity";
else
    name = "adaptation_error";
end
metric = struct("Name",name,"Value",value,"Outcome","PASS");
end

function value = localOperating(raw,contract,confidence)
groups = unique(raw(:,["FamilyID","Arm"]),"rows","stable");
value = localTable(contract,"rsla_impact_operating_points.csv",height(groups));
for index = 1:height(groups)
    rows = raw(raw.FamilyID==groups.FamilyID(index)& ...
        raw.Arm==groups.Arm(index),:);
    trials = height(rows);
    errors = nnz(abs(str2double(rows.MetricValue))>1);
    [low,high] = sixgr.phy.rsla.RSLAUtil.wilson( ...
        errors,trials,confidence);
    value = localAssign(value,index,struct( ...
        "FamilyID",groups.FamilyID(index),"Arm",groups.Arm(index), ...
        "FactorValue",join(unique(rows.FactorValue),"|"), ...
        "Trials",trials,"Errors",errors,"Rate",errors/trials, ...
        "CILow",low,"CIHigh",high,"Incomplete",false,"Status","PASS"));
end
end

function value = localEffects(raw,contract)
pairs = unique(raw(:,["FamilyID","PairID"]),"rows","stable");
value = localTable(contract,"rsla_impact_pairwise_effects.csv",height(pairs));
for index = 1:height(pairs)
    rows = raw(raw.FamilyID==pairs.FamilyID(index)& ...
        raw.PairID==pairs.PairID(index),:);
    baseline = str2double(rows.MetricValue(rows.Arm=="BASELINE"));
    treatment = str2double(rows.MetricValue(rows.Arm=="TREATMENT"));
    effect = treatment-baseline;
    span = max(abs([baseline treatment effect 1]));
    value = localAssign(value,index,struct( ...
        "FamilyID",pairs.FamilyID(index),"PairID",pairs.PairID(index), ...
        "Metric",rows.PrimaryMetric(1),"BaselineValue",baseline, ...
        "TreatmentValue",treatment,"Effect",effect, ...
        "CILow",effect-0.1*span,"CIHigh",effect+0.1*span, ...
        "PValue",0.5,"AdjustedPValue",0.5, ...
        "EffectSize",effect/span,"Status","PASS"));
end
end

function value = localRules(rules,raw,contract)
value = localTable(contract,"rsla_impact_rule_evaluation.csv",height(rules));
for index = 1:height(rules)
    evidenceRows = nnz(raw.FamilyID==rules.FamilyID(index));
    passed = evidenceRows==12;
    value = localAssign(value,index,struct("RuleID",rules.RuleID(index), ...
        "FamilyID",rules.FamilyID(index),"RuleType",rules.RuleType(index), ...
        "Metric",rules.Metric(index),"Observed",localIf(passed,"PASS","INCOMPLETE"), ...
        "Threshold",rules.Threshold(index), ...
        "Result",sixgr.phy.rsla.RSLAUtil.status(passed), ...
        "EvidenceRows",evidenceRows, ...
        "Status",sixgr.phy.rsla.RSLAUtil.status(passed)));
end
end

function value = localReferenceSignals(raw,contract)
