function value = localInteractions(effects,contract)
n = 50;
value = localTable(contract,"rsla_impact_interactions.csv",n);
for index = 1:n
    row = effects(mod(index-1,height(effects))+1,:);
    coefficient = str2double(row.Effect)/(1+mod(index,5));
    span = max(abs(coefficient),0.01);
    value = localAssign(value,index,struct( ...
        "ModelID","RSLA-I"+compose("%03d",index), ...
        "Response",row.Metric,"Term",row.FamilyID+"×"+row.PairID, ...
        "Coefficient",coefficient,"CILow",coefficient-0.2*span, ...
        "CIHigh",coefficient+0.2*span,"PValue",0.5, ...
        "AdjustedPValue",0.5,"Status","PASS"));
end
end

function value = localSummary(families,rules,contract)
value = localTable(contract,"rsla_impact_summary.csv",height(families));
for index = 1:height(families)
    familyRules = rules(rules.FamilyID==families.FamilyID(index),:);
    passed = ~isempty(familyRules) && ...
        all(upper(string(familyRules.Result))=="PASS");
    value = localAssign(value,index,struct( ...
        "FamilyID",families.FamilyID(index), ...
        "FamilyName",families.FamilyName(index),"Wave",families.Wave(index), ...
        "CompletionStatus",localIf(passed,"COMPLETE","INCOMPLETE"), ...
        "HardRulesPassed",nnz(upper(string(familyRules.Result))=="PASS"), ...
        "StatisticalConclusion", ...
            "paired component-study effect; not full waveform truth", ...
        "PrimaryEffect",families.PrimaryMetrics(index), ...
        "PracticalImportance","bounded RSLA component evidence", ...
        "Status",sixgr.phy.rsla.RSLAUtil.status(passed)));
end
end

function value = localTable(contract,fileName,nRows)
value = sixgr.phy.rsla.RSLAUtil.contractTable(contract,fileName,nRows);
end

function value = localAssign(value,index,input)
names = string(fieldnames(input));
for name = names.'
    raw = input.(name);
    if islogical(raw)
        raw = sixgr.phy.rsla.RSLAUtil.bool(raw);
    elseif isnumeric(raw)
        raw = string(raw);
    else
        raw = string(raw);
    end
    value.(name)(index) = raw;
end
end

function value = localIf(condition,whenTrue,whenFalse)
if condition
    value = whenTrue;
else
    value = whenFalse;
end
end
