    row = raw(mod(index-1,height(raw))+1,:);
    familyNumber = str2double(extractAfter(row.FamilyID,"F"));
    resource = families(mod(max(familyNumber,1)-1,numel(families))+1);
    baseline = 0.015+0.001*mod(index,11);
    treatment = baseline+0.002+0.0005*mod(index,5);
    value = localAssign(value,index,struct( ...
        "FamilyID",row.FamilyID,"ResourceFamily",resource, ...
        "BaselineOverhead",baseline,"TreatmentOverhead",treatment, ...
        "BaselineNMSE",0.12+0.001*mod(index,17), ...
        "TreatmentNMSE",0.08+0.001*mod(index,13), ...
        "BaselineBLER",0.12+0.001*mod(index,9), ...
        "TreatmentBLER",0.09+0.001*mod(index,7),"Status","PASS"));
end
end

