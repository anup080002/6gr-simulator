classdef LinkAdaptationDecisionEngine
    %LINKADAPTATIONDECISIONENGINE Measured-only steady-state authority.

    methods (Static)
        function decision = fromDecodedCSI(event,consumer,dataset,ollaState)
            if ~isa(event,"sixgr.phy.rsla.DecodedCSIReportEvent")
                error("RSLA:MissingMeasuredInput", ...
                    "Steady-state DL adaptation requires a decoded CSI event.");
            end
            data = event.Data;
            measurement = struct("UEID",data.UEID,"CellID",data.CellID, ...
                "BWPID",data.BWPID,"ResourceID",data.ResourceID, ...
                "BeamID",consumer.BeamID,"ConfigurationEpoch", ...
                data.ConfigurationEpoch,"ProducerSlot",data.ProducerSlot, ...
                "AvailableSlot",data.AvailableSlot);
            validity = sixgr.phy.rsla.MeasurementValidityChecker.validate( ...
                measurement,consumer);
            dataset = sixgr.phy.rsla.CQIMCSCalibrationDataset.validate(dataset);
            cqi = double(data.Fields.CQI);
            threshold = double(dataset.ThresholdDb(:));
            mcs = min(numel(threshold)-1,max(0,cqi));
            decision = struct("DecisionSource","DECODED_CSI_REPORT", ...
                "DecodedReportID",data.ReportID,"CQI",cqi,"MCS",mcs, ...
                "CalibrationDatasetID",string(dataset.DatasetID), ...
                "OLLAOffsetDb",ollaState.MarginDb, ...
                "BootstrapUsed",false,"ReportAgeSlots",validity.AgeSlots, ...
                "Status","PASS");
        end

        function decision = fromMeasuredSRS(soundingState,consumer,dataset)
            if ~isa(soundingState,"sixgr.phy.rsla.ULChannelSoundingState")
                error("RSLA:MissingMeasuredInput", ...
                    "Steady-state UL adaptation requires measured SRS state.");
            end
            srsDecision = soundingState.consume(consumer);
            dataset = sixgr.phy.rsla.CQIMCSCalibrationDataset.validate(dataset);
            decision = struct("DecisionSource","SRS_MEASURED", ...
                "DecodedReportID","","CQI",NaN, ...
                "MCS",max(0,double(srsDecision.SelectedRI)-1), ...
                "CalibrationDatasetID",string(dataset.DatasetID), ...
                "OLLAOffsetDb",0,"BootstrapUsed",false, ...
                "ReportAgeSlots",srsDecision.AgeSlots,"Status","PASS");
        end

        function rejectConfigured(varargin) %#ok<INUSD>
            error("RSLA:ConfiguredSNRForbidden", ...
                "Configured SNR/CQI/MCS cannot drive strict steady-state adaptation.");
        end
    end
end
