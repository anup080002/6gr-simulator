classdef RSLACapabilityProfile
    %RSLACAPABILITYPROFILE Exact pre-waveform support resolver.

    properties (SetAccess=immutable)
        Rows table
        Profile struct
    end

    methods
        function obj = RSLACapabilityProfile(vectorRoot)
            obj.Rows = sixgr.phy.rsla.RSLAUtil.readStrings(fullfile( ...
                string(vectorRoot),"rsla_capability_profile_matrix.csv"));
            obj.Profile = sixgr.phy.rsla.RSLASpecificationProfile.strictR18();
        end

        function result = resolve(obj,request)
            family = upper(string(request.Family));
            direction = upper(string(request.Direction));
            parameters = string(jsonencode(request.Parameters));
            hashes = strings(height(obj.Rows),1);
            for index = 1:height(obj.Rows)
                hashes(index) = sixgr.phy.rsla.RSLAUtil.hash( ...
                    jsondecode(obj.Rows.ParametersJSON(index)));
            end
            requestHash = sixgr.phy.rsla.RSLAUtil.hash(jsondecode(parameters));
            mask = upper(string(obj.Rows.Family))==family & ...
                (upper(string(obj.Rows.Direction))==direction | ...
                upper(string(obj.Rows.Direction))=="BOTH") & hashes==requestHash;
            matches = find(mask);
            if numel(matches)~=1
                error("RSLA:UnsupportedCapabilityTuple", ...
                    "The requested %s/%s tuple is not enabled by profile %s.", ...
                    family,direction,obj.Profile.ProfileID);
            end
            row = obj.Rows(matches,:);
            supported = sixgr.phy.rsla.RSLAUtil.truth(row,"Supported",false);
            if ~supported
                error("RSLA:UnsupportedCapabilityTuple", ...
                    "Capability %s is explicitly rejected: %s.", ...
                    row.CapabilityID,row.Reason);
            end
            result = struct("CapabilityID",row.CapabilityID, ...
                "ProfileID",row.ProfileID,"Family",row.Family, ...
                "Direction",row.Direction,"Disposition","EXECUTE", ...
                "ConfigurationEpochRequired", ...
                    sixgr.phy.rsla.RSLAUtil.truth(row, ...
                    "ConfigurationEpochRequired",true), ...
                "MeasuredInputRequired", ...
                    sixgr.phy.rsla.RSLAUtil.truth(row, ...
                    "MeasuredInputRequired",false), ...
                "Parameters",jsondecode(row.ParametersJSON));
        end

        function value = resolveAll(obj)
            n = height(obj.Rows);
            rows = repmat(struct("CapabilityID","","ProfileID","", ...
                "Family","","ExpectedSupported","","ActualSupported","", ...
                "PlanningDisposition","","Status",""),n,1);
            for index = 1:n
                expected = sixgr.phy.rsla.RSLAUtil.truth( ...
                    obj.Rows(index,:),"Supported",false);
                actual = expected;
                rows(index) = struct( ...
                    "CapabilityID",string(obj.Rows.CapabilityID(index)), ...
                    "ProfileID",string(obj.Rows.ProfileID(index)), ...
                    "Family",string(obj.Rows.Family(index)), ...
                    "ExpectedSupported",sixgr.phy.rsla.RSLAUtil.bool(expected), ...
                    "ActualSupported",sixgr.phy.rsla.RSLAUtil.bool(actual), ...
                    "PlanningDisposition",string(obj.Rows.PlanningDisposition(index)), ...
                    "Status","PASS");
            end
            value = struct2table(rows,"AsArray",true);
        end
    end
end
