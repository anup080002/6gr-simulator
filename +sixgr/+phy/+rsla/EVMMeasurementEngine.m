classdef EVMMeasurementEngine
    %EVMMEASUREMENTENGINE RE/reference-point-specific RMS EVM.

    methods (Static)
        function result = measure(estimate,reference,referencePoint)
            estimate = estimate(:);
            reference = reference(:);
            if numel(estimate)~=numel(reference) || isempty(reference) || ...
                    any(~isfinite(real(estimate))|~isfinite(imag(estimate))) || ...
                    any(~isfinite(real(reference))|~isfinite(imag(reference))) || ...
                    sum(abs(reference).^2)<=0
                error("RSLA:InvalidEVMReference", ...
                    "EVM requires aligned finite estimates and nonzero reference REs.");
            end
            allowed = ["equalized_data_RE","equalized_reference_RE", ...
                "transmitter_reference_point","receiver_equalized"];
            if ~ismember(string(referencePoint),allowed)
                error("RSLA:InvalidEVMReference", ...
                    "Unsupported EVM reference point %s.",string(referencePoint));
            end
            rmsValue = sqrt(sum(abs(estimate-reference).^2)/ ...
                sum(abs(reference).^2));
            result = struct("RMS",rmsValue,"Percent",100*rmsValue, ...
                "ReferencePoint",string(referencePoint), ...
                "RECount",numel(reference), ...
                "Claim","receiver_waveform_implementation_metric_only");
        end
    end
end
