classdef CSIReportConfigurationState
    %CSIREPORTCONFIGURATIONSTATE Immutable report-dependent bit ownership.

    properties (SetAccess=immutable)
        Data struct
    end

    methods
        function obj = CSIReportConfigurationState(row)
            profile = sixgr.phy.rsla.RSLAUtil.text(row,"ReportProfileID","");
            transport = upper(sixgr.phy.rsla.RSLAUtil.text(row,"Transport",""));
            trigger = lower(sixgr.phy.rsla.RSLAUtil.text(row,"TriggerType",""));
            p1 = sixgr.phy.rsla.RSLAUtil.number(row,"Part1InformationBits",NaN);
            p2 = sixgr.phy.rsla.RSLAUtil.number(row,"Part2InformationBits",NaN);
            expected = localLayout(profile);
            valid = ismember(transport,["PUCCH","PUSCH"]) && ...
                ismember(trigger,["periodic","semipersistent","aperiodic"]) && ...
                ~(transport=="PUSCH" && trigger=="periodic") && ...
                sum(expected.Part1Widths)==p1 && sum(expected.Part2Widths)==p2;
            if ~valid
                error("RSLA:InvalidCSIReportConfiguration", ...
                    "CSI report configuration %s has invalid transport, trigger or length.", ...
                    profile);
            end
            obj.Data = struct("ReportProfileID",profile, ...
                "ReportQuantity",sixgr.phy.rsla.RSLAUtil.text( ...
                    row,"ReportQuantity",""), ...
                "Transport",transport,"TriggerType",trigger, ...
                "ResourceConfigID",sixgr.phy.rsla.RSLAUtil.text( ...
                    row,"ResourceConfigID",""), ...
                "MeasurementResourceSetID",sixgr.phy.rsla.RSLAUtil.text( ...
                    row,"MeasurementResourceSetID",""), ...
                "InterferenceResourceSetID",sixgr.phy.rsla.RSLAUtil.text( ...
                    row,"InterferenceResourceSetID",""), ...
                "Part1Fields",expected.Part1Fields, ...
                "Part1Widths",expected.Part1Widths, ...
                "Part2Fields",expected.Part2Fields, ...
                "Part2Widths",expected.Part2Widths, ...
                "Part1Bits",p1,"Part2Bits",p2, ...
                "ConfigurationEpoch",1);
        end
    end
end

function value = localLayout(profile)
switch string(profile)
    case "CSI-P01"
        value = local(["CRI","RI","CQI"],[3 2 4],strings(1,0),zeros(1,0));
    case "CSI-P02"
        value = local(["CRI","RI","PMI_i1","CQI"],[3 2 4 4],"PMI_i2",3);
    case "CSI-P03"
        value = local(["CRI","RI","LI","PMI_i1","CQI"],[4 3 2 5 4], ...
            ["PMI_i2","SubbandCQI"],[5 8]);
    case "CSI-P04"
        value = local(["SSBRI","RSRP"],[3 7],strings(1,0),zeros(1,0));
    case "CSI-P05"
        value = local(["CRI","RSRP"],[4 7],strings(1,0),zeros(1,0));
    case "CSI-P06"
        value = local(["CRI","RI","CQI"],[4 3 4], ...
            ["PMI","SubbandCQI"],[12 16]);
    case "CSI-P07"
        value = local(["CRI","RI","CQI"],[4 2 4], ...
            ["BeamIndices","AmplitudeCoefficients","PhaseCoefficients"], ...
            [12 16 16]);
    case "CSI-P08"
        value = local(["CRI","RI","CQI"],[3 2 4], ...
            ["PMI","SubbandCQI"],[10 12]);
    otherwise
        error("RSLA:InvalidCSIReportConfiguration", ...
            "Unsupported report profile %s.",string(profile));
end
end

function value = local(p1f,p1w,p2f,p2w)
value = struct("Part1Fields",string(p1f),"Part1Widths",double(p1w), ...
    "Part2Fields",string(p2f),"Part2Widths",double(p2w));
end
