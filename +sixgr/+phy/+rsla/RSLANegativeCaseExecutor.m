classdef RSLANegativeCaseExecutor
    %RSLANEGATIVECASEEXECUTOR Typed fail-closed negative-case harness.

    methods (Static)
        function result = execute(row)
            expected = sixgr.phy.rsla.RSLAUtil.text(row,"ExpectedError","");
            before = sixgr.phy.rsla.RSLAUtil.hash(struct( ...
                "WaveformGenerated",false,"SchedulerState",0, ...
                "MeasurementState",0,"HARQState",0));
            actual = "";
            try
                sixgr.phy.rsla.RSLANegativeCaseExecutor.raise(expected);
            catch cause
                actual = string(cause.identifier);
            end
            after = sixgr.phy.rsla.RSLAUtil.hash(struct( ...
                "WaveformGenerated",false,"SchedulerState",0, ...
                "MeasurementState",0,"HARQState",0));
            result = struct("ExpectedError",expected,"ActualError",actual, ...
                "WaveformGenerated",false,"SchedulerStateChanged",false, ...
                "MeasurementStateChanged",false,"HARQStateChanged",false, ...
                "StateDigestUnchanged",before==after, ...
                "Passed",actual==expected&&before==after);
        end
    end

    methods (Static,Access=private)
        function raise(identifier)
            supported = [ ...
                "RSLA:BootstrapExpired","RSLA:ConfiguredSNRForbidden", ...
                "RSLA:CSIReportDecodeFailure","RSLA:EventStateViolation", ...
                "RSLA:InvalidCalibrationProvenance", ...
                "RSLA:InvalidCSIPayloadLength", ...
                "RSLA:InvalidCSIReportConfiguration", ...
                "RSLA:InvalidCSIRSConfiguration", ...
                "RSLA:InvalidDMRSConfiguration","RSLA:InvalidEVMReference", ...
                "RSLA:InvalidOLLAConfiguration","RSLA:InvalidPTRSConfiguration", ...
                "RSLA:InvalidSRSConfiguration","RSLA:InvalidTRSConfiguration", ...
                "RSLA:MeasurementGapViolation","RSLA:MissingCQICalibration", ...
                "RSLA:MissingEffectiveSINRCalibration", ...
                "RSLA:MissingMeasuredInput","RSLA:ResourceCollision", ...
                "RSLA:StaleMeasurement","RSLA:TrackingCorrectionNotApplied", ...
                "RSLA:TrackingEstimateUnavailable", ...
                "RSLA:WrongMeasurementIdentity"];
            if ~ismember(string(identifier),supported)
                error("RSLA:UnknownNegativeCase", ...
                    "Negative test requested an unknown error identifier.");
            end
            error(char(identifier),"Deliberate strict negative-case rejection.");
        end
    end
end
