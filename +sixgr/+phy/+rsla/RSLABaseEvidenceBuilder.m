classdef RSLABaseEvidenceBuilder
    %RSLABASEEVIDENCEBUILDER Executed Phase-09 production evidence.

    methods (Static)
        function [tables,summary] = build(root,contract,runID,seeds,confidence)
            startTime = string(datetime("now","TimeZone","UTC"));
            failures = 0;
            trials = 0;
            profile = sixgr.phy.rsla.RSLACapabilityProfile(root);
            tables = struct();
            tables.rsla_capability_resolution = profile.resolveAll();
            expectedSupported = upper(string( ...
                tables.rsla_capability_resolution.ExpectedSupported))=="TRUE";

            [tables.rsla_dmrs_matrix,dmrsPlans,dmrsMismatch,n] = ...
                localDMRS(root,contract);
            trials = trials+n; failures = failures+dmrsMismatch;
            [tables.rsla_csirs_matrix,csirsPlans,csirsMismatch,n] = ...
                localCSIRS(root,contract);
            trials = trials+n; failures = failures+csirsMismatch;
            [tables.rsla_srs_matrix,srsPlans,srsMismatch,n] = ...
                localSRS(root,contract);
            trials = trials+n; failures = failures+srsMismatch;
            tables.rsla_resource_ownership = localOwnership( ...
                contract,runID,dmrsPlans,csirsPlans,srsPlans);
            [tables.rsla_collision_resolution,collisionMismatch,n] = ...
                localCollision(root,contract);
            trials = trials+n; failures = failures+collisionMismatch;
            [tables.rsla_trs_tracking,trsMismatch,n] = localTRS(root,contract);
            trials = trials+n; failures = failures+trsMismatch;
            [tables.rsla_ptrs_tracking,ptrsMismatch,n] = localPTRS(root,contract);
            trials = trials+n; failures = failures+ptrsMismatch;
            tables.rsla_measurement_registry = localMeasurementRegistry(contract);
            [tables.rsla_measurement_results,measurementMismatch,n] = ...
                localMeasurements(root,contract);
            trials = trials+n; failures = failures+measurementMismatch;
            [tables.rsla_measurement_filter_trace,filterMismatch,n] = ...
                localFilter(root,contract);
            trials = trials+n; failures = failures+filterMismatch;
            [tables.rsla_measurement_gap_trace,gapMismatch,n] = ...
                localGaps(root,contract);
            trials = trials+n; failures = failures+gapMismatch;
            [tables.rsla_rrm_event_trace,rrmMismatch,n] = ...
                localRRM(root,contract);
            trials = trials+n; failures = failures+rrmMismatch;
            [tables.rsla_srs_scheduler_consumption,srsStateMismatch,n] = ...
                localSRSAuthority(root,contract);
            trials = trials+n; failures = failures+srsStateMismatch;
            [tables.rsla_csi_report_resolution, ...
                tables.rsla_csi_bit_ownership, ...
                tables.rsla_csi_uci_roundtrip,csiMismatch,n] = ...
                localCSI(root,contract);
            trials = trials+n; failures = failures+csiMismatch;
            [tables.rsla_measured_state_validity,stateMismatch,n] = ...
                localMeasuredState(root,contract);
            trials = trials+n; failures = failures+stateMismatch;
            [tables.rsla_link_adaptation_decisions,laMismatch,n] = ...
                localLinkAdaptation(root,contract);
            trials = trials+n; failures = failures+laMismatch;
            [tables.rsla_bootstrap_transition,bootstrapMismatch,n] = ...
                localBootstrap(root,contract);
            trials = trials+n; failures = failures+bootstrapMismatch;
            [tables.rsla_cqi_mcs_calibration, ...
                tables.rsla_effective_sinr_calibration] = ...
                localCalibration(root,contract);
            [tables.rsla_effective_sinr_trials,effectiveMismatch,n] = ...
                localEffectiveSINR(root,contract);
            trials = trials+n; failures = failures+effectiveMismatch;
            [tables.rsla_olla_state,ollaMismatch,n] = localOLLA(root,contract);
            trials = trials+n; failures = failures+ollaMismatch;
            tables.rsla_olla_convergence = localOLLAConvergence( ...
                contract,seeds,confidence);
            [tables.rsla_evm_measurements,evmMismatch,n] = ...
                localEVM(root,contract);
            trials = trials+n; failures = failures+evmMismatch;
            tables.rsla_negative_tests = localNegative(root,contract);
            tables.rsla_receiver_metrics = localReceiverMetrics(contract,seeds);
            tables.rsla_independent_vector_results = localIndependent( ...
                root,contract,tables);
            independentMismatch = sum(str2double( ...
                tables.rsla_independent_vector_results.MismatchCount));
            failures = failures+independentMismatch;
            tables.rsla_test_summary = localTestSummary(contract);

            summary = struct("StartTime",startTime, ...
                "CapabilityExecuteCount",nnz(expectedSupported), ...
                "CapabilityRejectCount",nnz(~expectedSupported), ...
                "IndependentMismatchCount",independentMismatch, ...
                "ComponentTrials",trials,"Failures",failures);
        end
    end
end

function [value,plans,mismatches,trials] = localDMRS(root,contract)
input = localRead(root,"rsla_dmrs_test_vectors.csv");
value = localTable(contract,"rsla_dmrs_matrix.csv",height(input));
plans = {};
mismatches = 0;
for index = 1:height(input)
    expectedReject = upper(string(input.ExpectedDisposition(index)))=="REJECT";
    actualReject = false;
    actualError = "";
    plan = struct("IndexSHA256",sixgr.phy.rsla.RSLAUtil.hash([]), ...
        "SequenceSHA256",sixgr.phy.rsla.RSLAUtil.hash([]));
    try
        plan = sixgr.phy.rsla.SharedDMRSEngine.planVector(input(index,:));
        plans{end+1,1} = struct("Type","DMRS","CaseID", ...
            string(input.CaseID(index)),"Plan",plan); %#ok<AGROW>
    catch cause
        actualReject = true;
        actualError = string(cause.identifier);
    end
    mismatch = expectedReject~=actualReject;
    if expectedReject, mismatch = mismatch || actualError~= ...
            string(input.ExpectedError(index)); end
    mismatches = mismatches+double(mismatch);
    row = struct("CaseID",input.CaseID(index), ...
        "Direction",input.Direction(index), ...
        "MappingType",input.MappingType(index), ...
        "ConfigurationType",input.ConfigurationType(index), ...
        "Length",input.Length(index), ...
        "AdditionalPosition",input.AdditionalPosition(index), ...
        "LogicalPorts",input.LogicalPorts(index), ...
        "REIndexSHA256",plan.IndexSHA256, ...
        "SequenceSHA256",plan.SequenceSHA256, ...
        "MismatchCount",double(mismatch),"Status", ...
        sixgr.phy.rsla.RSLAUtil.status(~mismatch));
    value = localAssign(value,index,row);
end
trials = height(input);
end

function [value,plans,mismatches,trials] = localCSIRS(root,contract)
input = localRead(root,"rsla_csirs_test_vectors.csv");
value = localTable(contract,"rsla_csirs_matrix.csv",height(input));
value.ActualDisposition = strings(height(input),1);
value.ActualError = strings(height(input),1);
value.WaveformGenerated = strings(height(input),1);
plans = {};
mismatches = 0;
for index = 1:height(input)
    expectedReject = upper(string(input.ExpectedDisposition(index)))=="REJECT";
    actualReject = false;
    actualError = "";
    plan = struct("IndexSHA256",sixgr.phy.rsla.RSLAUtil.hash([]), ...
        "SequenceSHA256",sixgr.phy.rsla.RSLAUtil.hash([]));
    try
        plan = sixgr.phy.rsla.CSIRSResourceEngine.planVector(input(index,:));
        plans{end+1,1} = struct("Type",string(input.ResourceType(index)), ...
            "CaseID",string(input.CaseID(index)),"Plan",plan); %#ok<AGROW>
    catch cause
        actualReject = true;
        actualError = string(cause.identifier);
    end
    specLookup = upper(string(input.ExpectedDisposition(index)))== ...
        "SPEC_LOOKUP_REQUIRED";
    if expectedReject
        mismatch = ~actualReject || actualError~= ...
            string(input.ExpectedError(index));
    elseif specLookup && actualReject
        mismatch = ~ismember(actualError, ...
            ["RSLA:InvalidCSIRSConfiguration", ...
            "RSLA:UnsupportedCapabilityTuple"]);
    else
        mismatch = actualReject;
    end
    mismatches = mismatches+double(mismatch);
    row = struct("CaseID",input.CaseID(index),"Row",input.Row(index), ...
        "Ports",input.Ports(index),"Density",input.Density(index), ...
        "CDMType",input.CDMType(index), ...
        "ResourceType",input.ResourceType(index), ...
        "TriggerType",input.TriggerType(index), ...
        "REIndexSHA256",plan.IndexSHA256, ...
        "SequenceSHA256",plan.SequenceSHA256, ...
        "ActualDisposition",localIf(actualReject,"REJECT","EXECUTE"), ...
        "ActualError",actualError, ...
        "WaveformGenerated",~actualReject, ...
        "MismatchCount",double(mismatch),"Status", ...
        sixgr.phy.rsla.RSLAUtil.status(~mismatch));
    value = localAssign(value,index,row);
end
trials = height(input);
end

