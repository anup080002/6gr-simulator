mismatches = 0;
cases = unique(input.CaseID,"stable");
cursor = 0;
for caseIndex = 1:numel(cases)
    rows = input(input.CaseID==cases(caseIndex),:);
    actual = sixgr.phy.rsla.L3MeasurementFilter.apply( ...
        str2double(rows.InputValueDb),str2double(rows.FilterCoefficientK(1)));
    for index = 1:height(rows)
        cursor = cursor+1;
        expected = str2double(rows.ExpectedFilteredValueDb(index));
        mismatch = abs(actual.Filtered(index)-expected)>1e-7;
        mismatches = mismatches+double(mismatch);
        value = localAssign(value,cursor,struct("CaseID",rows.CaseID(index), ...
            "Quantity",rows.Quantity(index),"SampleIndex",rows.SampleIndex(index), ...
            "RawValueDb",rows.InputValueDb(index), ...
            "FilteredValueDb",actual.Filtered(index), ...
            "ExpectedValueDb",expected,"FilterK",rows.FilterCoefficientK(index), ...
            "Status",sixgr.phy.rsla.RSLAUtil.status(~mismatch)));
    end
end
trials = height(input);
end

