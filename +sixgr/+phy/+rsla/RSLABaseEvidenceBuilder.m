function [value,mismatches,trials] = localSRSAuthority(root,contract)
input = localRead(root,"rsla_srs_scheduler_state_vectors.csv");
value = localTable(contract,"rsla_srs_scheduler_consumption.csv",height(input));
mismatches = 0;
for index = 1:height(input)
    data = struct("MeasurementID",input.CaseID(index), ...
        "UEID",str2double(input.UEID(index)), ...
        "CellID",str2double(input.ServingCellID(index)), ...
        "BWPID",str2double(input.BWPID(index)), ...
        "ResourceID",input.ResourceID(index),"BeamID","1", ...
        "ProducerSlot",str2double(input.MeasurementSlot(index)), ...
        "AvailableSlot",str2double(input.MeasurementSlot(index)), ...
        "ConfigurationEpoch",1, ...
        "ChannelEstimateSHA256",input.ChannelEstimateSHA256(index), ...
        "CovarianceSHA256",input.CovarianceSHA256(index), ...
        "MeasuredRI",str2double(input.MeasuredRI(index)), ...
        "MeasuredSRI",str2double(input.MeasuredSRI(index)), ...
        "MeasuredTPMI",str2double(input.MeasuredTPMI(index)), ...
        "CalibrationValid",sixgr.phy.rsla.RSLAUtil.truth( ...
        input(index,:),"ReciprocityCalibrationValid",false), ...
        "CovarianceValid",sixgr.phy.rsla.RSLAUtil.truth( ...
        input(index,:),"CovarianceValid",false));
    state = sixgr.phy.rsla.ULChannelSoundingState(data);
    consumer = struct("UEID",data.UEID,"CellID",data.CellID, ...
        "BWPID",data.BWPID,"ResourceID",data.ResourceID,"BeamID","1", ...
        "ConfigurationEpoch",1, ...
        "ConsumerSlot",str2double(input.ConsumptionSlot(index)), ...
        "MaxAgeSlots",str2double(input.MaxAgeSlots(index)));
    if ~sixgr.phy.rsla.RSLAUtil.truth(input(index,:),"CorrectUE",true)
        consumer.UEID = consumer.UEID+100;
    end
    if ~sixgr.phy.rsla.RSLAUtil.truth(input(index,:),"CorrectResource",true)
        consumer.ResourceID = "WRONG";
    end
    valid = false;
    selected = struct("SelectedRI",NaN,"SelectedSRI",NaN, ...
        "SelectedTPMI",NaN,"SelectedPrecoderSHA256","", ...
        "AppliedPrecoderSHA256","");
    try
        selected = state.consume(consumer);
        valid = true;
    catch
        valid = false;
    end
    expected = sixgr.phy.rsla.RSLAUtil.truth( ...
        input(index,:),"ExpectedConsumable",false);
    mismatch = valid~=expected;
    mismatches = mismatches+double(mismatch);
    value = localAssign(value,index,struct("CaseID",input.CaseID(index), ...
        "UEID",input.UEID(index),"MeasurementID",input.CaseID(index), ...
        "AgeSlots",input.AgeSlots(index),"Valid",valid, ...
        "SelectedRI",selected.SelectedRI,"SelectedSRI",selected.SelectedSRI, ...
