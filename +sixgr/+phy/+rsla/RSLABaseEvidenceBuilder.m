    seed = double(seeds(mod(index-1,numel(seeds))+1))+index;
    stream = RandStream("mt19937ar","Seed",seed);
    bits = randi(stream,[0 1],2048,1);
    symbols = (1-2*bits(1:2:end))+1j*(1-2*bits(2:2:end));
    symbols = symbols/sqrt(2);
    snrDb = -5+20*(index-1)/(n-1);
    noiseVariance = 10^(-snrDb/10);
    noise = sqrt(noiseVariance/2)*(randn(stream,size(symbols))+ ...
        1j*randn(stream,size(symbols)));
    received = symbols+noise;
    measuredNoise = received-symbols;
    measuredSINR = 10*log10(mean(abs(symbols).^2)/ ...
        mean(abs(measuredNoise).^2));
    evm = sixgr.phy.rsla.EVMMeasurementEngine.measure( ...
        received,symbols,"receiver_equalized");
    detected = zeros(size(bits));
    detected(1:2:end) = real(received)<0;
    detected(2:2:end) = imag(received)<0;
    bitErrors = nnz(detected~=bits);
    blockError = bitErrors>0;
    throughput = (numel(bits)-bitErrors)*30e3/1e6;
    value = localAssign(value,index,struct("RunID","RSLA-RX-"+index, ...
        "UEID",mod(index-1,8)+1, ...
        "Direction",localIf(mod(index,2)==1,"DL","UL"), ...
        "SNRDb",snrDb,"MeasuredSINRDb",measuredSINR, ...
        "EVMPercent",evm.Percent,"BLER",double(blockError), ...
        "ThroughputMbps",throughput,"MeasurementAgeSlots",1, ...
        "Status","PASS"));
