function [value,mismatches,trials] = localMeasurements(root,contract)
input = localRead(root,"expected_rsla_measurement_analytical_vectors.csv");
value = localTable(contract,"rsla_measurement_results.csv",height(input));
mismatches = 0;
for index = 1:height(input)
    request = struct("MeasurementID",input.CaseID(index), ...
        "Quantity",input.Quantity(index), ...
        "ReferenceSignalPowerW",str2double(input.ReferenceSignalPowerW(index)), ...
        "InterferencePowerW",str2double(input.InterferencePowerW(index)), ...
        "NoisePowerW",str2double(input.NoisePowerW(index)), ...
        "RSSIPowerW",str2double(input.RSSIPowerW(index)), ...
        "NRB",str2double(input.NRB(index)),"ResourceID","RS-1", ...
        "BeamID",input.BeamID(index),"UEID",1,"CellID",1,"BWPID",1, ...
        "ProducerSlot",index,"AvailableSlot",index, ...
        "ConfigurationEpoch",1,"SourceSHA256", ...
        sixgr.phy.rsla.RSLAUtil.hash(input(index,:)), ...
        "Confidence",1,"ResourceAvailable",true,"Muted",false);
    actual = sixgr.phy.rsla.MeasurementRegistryR18.measure(request);
    expected = str2double(input.ExpectedValue(index));
    errorValue = abs(actual.Value-expected);
    tolerance = 1e-7;
    mismatch = errorValue>tolerance;
    mismatches = mismatches+double(mismatch);
    value = localAssign(value,index,struct("CaseID",input.CaseID(index), ...
        "Quantity",input.Quantity(index),"MeasuredValue",actual.Value, ...
        "ExpectedValue",expected,"AbsoluteError",errorValue, ...
        "Tolerance",tolerance,"ResourceID",actual.ResourceID, ...
        "BeamID",actual.BeamID,"AgeSlots",0, ...
        "Provenance",actual.Provenance, ...
        "Status",sixgr.phy.rsla.RSLAUtil.status(~mismatch)));
end
trials = height(input);
end

function [value,mismatches,trials] = localFilter(root,contract)
