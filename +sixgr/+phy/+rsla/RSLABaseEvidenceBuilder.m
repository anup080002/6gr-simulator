function value = localRRMCondition(row)
eventID = upper(string(row.EventID));
ms = str2double(row.ServingMeasurementDb);
mn = str2double(row.NeighborMeasurementDb);
t1 = str2double(row.Threshold1Db);
t2 = str2double(row.Threshold2Db);
offset = str2double(row.OffsetDb);
hysteresis = str2double(row.HysteresisDb);
switch eventID
    case "A1", value = ms-hysteresis>t1;
    case "A2", value = ms+hysteresis<t1;
    case "A3", value = mn-hysteresis>ms+offset;
    case "A4", value = mn-offset-hysteresis>t1;
    case "A5", value = ms+hysteresis<t1 && mn-hysteresis>t2;
    case "A6", value = mn-hysteresis>ms+offset;
    otherwise
        error("RSLA:EventStateViolation","Unsupported RRM event.");
end
end

function value = localRead(root,fileName)
value = sixgr.phy.rsla.RSLAUtil.readStrings(fullfile(root,fileName));
end

function value = localTable(contract,fileName,n)
value = sixgr.phy.rsla.RSLAUtil.contractTable(contract,fileName,n);
end

function row = localAppend(value)
row = sixgr.phy.rsla.RSLAUtil.appendLike(value);
end

function value = localAssign(value,index,data)
fields = string(fieldnames(data));
available = string(value.Properties.VariableNames);
for field = fields.'
    if ismember(field,available)
        value.(field)(index) = string(data.(char(field)));
    end
end
end

function value = localIf(condition,yes,no)
if condition, value = yes; else, value = no; end
end
