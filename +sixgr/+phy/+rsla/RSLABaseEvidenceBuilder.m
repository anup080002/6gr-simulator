function value = localOwnership(contract,runID,varargin)
value = localTable(contract,"rsla_resource_ownership.csv",0);
for groupIndex = 1:numel(varargin)
    plans = varargin{groupIndex};
    for planIndex = 1:numel(plans)
        item = plans{planIndex};
        indices = double(item.Plan.IndicesZeroBased(:));
        for index = 1:min(numel(indices),128)
            linear = indices(index);
            subcarrierAbsolute = mod(linear,52*12);
            symbol = mod(floor(linear/(52*12)),14);
            port = floor(linear/(52*12*14));
            row = localAppend(value);
            row = localAssign(row,1,struct("RunID",runID,"Slot",0, ...
                "Symbol",symbol,"PRB",floor(subcarrierAbsolute/12), ...
                "Subcarrier",mod(subcarrierAbsolute,12), ...
                "ResourceType",item.Type,"ResourceID",item.CaseID, ...
                "OwnerUE",1,"Port",port, ...
                "OrthogonalityID",item.CaseID+"-P"+port, ...
                "CollisionStatus","resolved_before_waveform","Status","PASS"));
            value = [value;row]; %#ok<AGROW>
            if height(value)>=600, return; end
        end
    end
end
if height(value)<500
    error("RSLA:IncompleteEvidence", ...
        "Executed resource plans produced only %d ownership rows.",height(value));
end
end

function [value,mismatches,trials] = localCollision(root,contract)
input = localRead(root,"rsla_collision_test_vectors.csv");
value = localTable(contract,"rsla_collision_resolution.csv",height(input));
mismatches = 0;
for index = 1:height(input)
    actual = sixgr.phy.rsla.ReferenceSignalCollisionResolver.resolveVector( ...
        input(index,:));
    expectedCollision = sixgr.phy.rsla.RSLAUtil.truth( ...
        input(index,:),"ExpectedCollision",false);
    if expectedCollision, expectedDisposition = "COLLISION"; ...
    elseif actual.OrthogonalityProven && actual.OverlapCount>0
        expectedDisposition = "ORTHOGONAL_SHARE";
    else, expectedDisposition = "PASS"; end
    mismatch = actual.OverlapCount~=str2double(input.ExpectedOverlapCount(index)) || ...
        actual.Collision~=expectedCollision;
    mismatches = mismatches+double(mismatch);
    value = localAssign(value,index,struct("CaseID",input.CaseID(index), ...
        "ResourceA",input.ResourceAType(index), ...
        "ResourceB",input.ResourceBType(index), ...
        "OverlapCount",actual.OverlapCount, ...
        "OrthogonalityProven",actual.OrthogonalityProven, ...
        "ExpectedDisposition",expectedDisposition, ...
        "ActualDisposition",actual.Disposition, ...
        "Status",sixgr.phy.rsla.RSLAUtil.status(~mismatch)));
end
trials = height(input);
end

