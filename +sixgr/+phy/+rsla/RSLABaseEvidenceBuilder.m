function [value,mismatches,trials] = localPTRS(root,contract)
input = localRead(root,"rsla_ptrs_tracking_test_vectors.csv");
value = localTable(contract,"rsla_ptrs_tracking.csv",height(input));
mismatches = 0;
for index = 1:height(input)
    expectedReject = upper(string(input.ExpectedDisposition(index)))=="REJECT";
    actualReject = false;
    actualError = "";
    result = struct("CPEBeforeRad",0,"CPEAfterRad",0, ...
        "EVMBeforePercent",0,"EVMAfterPercent",0);
    try
        plan = sixgr.phy.rsla.PTRSResourceEngine.planVector(input(index,:));
        result = sixgr.phy.rsla.CommonPhaseErrorTracker.correct( ...
            plan,input.PhaseNoiseProfile(index));
    catch cause
        actualReject = true;
        actualError = string(cause.identifier);
    end
    mismatch = expectedReject~=actualReject;
    if expectedReject, mismatch = mismatch || actualError~= ...
            string(input.ExpectedError(index)); end
    if ~actualReject
        mismatch = mismatch || result.EVMAfterPercent>result.EVMBeforePercent+1e-9;
    end
    mismatches = mismatches+double(mismatch);
    value = localAssign(value,index,struct("CaseID",input.CaseID(index), ...
        "Direction",input.Direction(index), ...
        "TimeDensity",input.TimeDensity(index), ...
        "FrequencyDensity",input.FrequencyDensity(index), ...
        "CPEBeforeRad",result.CPEBeforeRad, ...
        "CPEAfterRad",result.CPEAfterRad, ...
        "EVMBeforePercent",result.EVMBeforePercent, ...
        "EVMAfterPercent",result.EVMAfterPercent, ...
        "BLER",double(~actualReject&&result.EVMAfterPercent>20), ...
        "Status",sixgr.phy.rsla.RSLAUtil.status(~mismatch)));
end
trials = height(input);
end

