classdef CSIRSResourceEngine
    %CSIRSRESOURCEENGINE Exact selected CSI-RS/CSI-IM resource planner.

    methods (Static)
        function plan = planVector(row)
            rowNumber = sixgr.phy.rsla.RSLAUtil.number(row,"Row",NaN);
            ports = sixgr.phy.rsla.RSLAUtil.number(row,"Ports",NaN);
            density = sixgr.phy.rsla.RSLAUtil.text(row,"Density","");
            cdmType = sixgr.phy.rsla.RSLAUtil.text(row,"CDMType","");
            resourceType = upper(sixgr.phy.rsla.RSLAUtil.text( ...
                row,"ResourceType",""));
            triggerType = lower(sixgr.phy.rsla.RSLAUtil.text( ...
                row,"TriggerType",""));
            firstSymbol = sixgr.phy.rsla.RSLAUtil.number( ...
                row,"FirstSymbol",NaN);
            secondSymbol = sixgr.phy.rsla.RSLAUtil.number( ...
                row,"SecondSymbol",NaN);
            subcarrier = sixgr.phy.rsla.RSLAUtil.number( ...
                row,"SubcarrierLocation",NaN);
            periodicity = sixgr.phy.rsla.RSLAUtil.number( ...
                row,"PeriodicitySlots",NaN);
            offset = sixgr.phy.rsla.RSLAUtil.number( ...
                row,"OffsetSlots",NaN);
            nid = sixgr.phy.rsla.RSLAUtil.number(row,"ScramblingID",NaN);
            expectedPorts = [1 1 2 4 4 8];
            expectedDensity = ["three","one","one","one","dot5even","one"];
            expectedCDM = ["nocdm","nocdm","fd-cdm2","fd-cdm2", ...
                "fd-cdm2","cdm4-fd2-td2"];
            supportedRow = ismember(rowNumber,1:6);
            periodicTimingValid = ...
                (triggerType=="aperiodic" && isnan(periodicity) && ...
                    isfinite(offset) && offset>=0) || ...
                (triggerType~="aperiodic" && isfinite(periodicity) && ...
                    periodicity>=1 && isfinite(offset) && offset>=0 && ...
                    offset<periodicity);
            valid = supportedRow && expectedPorts(rowNumber)==ports && ...
                lower(string(density))==lower(expectedDensity(rowNumber)) && ...
                lower(string(cdmType))==expectedCDM(rowNumber) && ...
                ismember(resourceType,["NZP","ZP","CSI-IM_ASSOCIATED"]) && ...
                ismember(triggerType,["periodic","semipersistent","aperiodic"]) && ...
                isfinite(firstSymbol) && firstSymbol>=0 && firstSymbol<=13 && ...
                isfinite(subcarrier) && subcarrier>=0 && subcarrier<=11 && ...
                periodicTimingValid && ...
                isfinite(nid) && nid>=0 && nid<=1023 && ...
                ~(rowNumber==6 && ~isfinite(secondSymbol));
            if ~valid
                error("RSLA:InvalidCSIRSConfiguration", ...
                    "Invalid CSI-RS/CSI-IM tuple for the bounded Release-18 profile.");
            end

            carrier = nrCarrierConfig("NSizeGrid",52, ...
                "SubcarrierSpacing",30,"NCellID",1,"NSlot",offset);
            cfg = nrCSIRSConfig;
            try
                cfg.RowNumber = rowNumber;
                cfg.Density = char(density);
                cfg.SymbolLocations = firstSymbol;
                if isfinite(secondSymbol)
                    cfg.SymbolLocations = [firstSymbol secondSymbol];
                end
                if rowNumber==6
                    cfg.SubcarrierLocations = mod(subcarrier+[0 3 6 9],12);
                else
                    cfg.SubcarrierLocations = subcarrier;
                end
                cfg.NumRB = carrier.NSizeGrid;
                cfg.RBOffset = 0;
                cfg.NID = nid;
                cfg.CSIRSType = char(localIf(transmittedType(resourceType), ...
                    "nzp","zp"));
                if isfinite(periodicity)
                    cfg.CSIRSPeriod = [periodicity offset];
                else
                    cfg.CSIRSPeriod = "on";
                end
                if lower(string(cfg.CDMType))~=lower(string(cdmType))
                    error("RSLA:UnsupportedCapabilityTuple", ...
                        "Installed 5G Toolbox maps row %d to %s, not %s.", ...
                        rowNumber,string(cfg.CDMType),string(cdmType));
                end
                [indices,symbols] = sixgr.phy.refsig.csirs( ...
                    carrier,cfg,"IndexBase","0based");
            catch cause
                wrapped = MException("RSLA:InvalidCSIRSConfiguration", ...
                    "Toolbox rejected the exact CSI-RS tuple: %s.",cause.message);
                wrapped = addCause(wrapped,cause);
                throw(wrapped);
            end
            transmitted = transmittedType(resourceType);
            if ~transmitted, symbols = zeros(size(symbols),"like",symbols); end
            plan = struct("ResourceType",resourceType, ...
                "TriggerType",triggerType,"Row",rowNumber,"Ports",ports, ...
                "IndicesZeroBased",double(indices(:)),"Symbols",symbols(:), ...
                "Muted",~transmitted,"PeriodicitySlots",periodicity, ...
                "OffsetSlots",offset,"ConfigurationEpoch",1, ...
                "IndexSHA256",sixgr.phy.rsla.RSLAUtil.hash(double(indices(:))), ...
                "SequenceSHA256",sixgr.phy.rsla.RSLAUtil.hash( ...
                    [real(symbols(:)) imag(symbols(:))]), ...
                "ExecutionBackend","matlab_5g_toolbox_waveform_kernel", ...
                "ApproximationMode","none");
        end
    end
end

function value = transmittedType(resourceType)
value = upper(string(resourceType))=="NZP";
end

function value = localIf(condition,yes,no)
if condition, value = yes; else, value = no; end
end
