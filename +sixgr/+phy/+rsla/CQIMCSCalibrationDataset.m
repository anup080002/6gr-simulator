classdef CQIMCSCalibrationDataset
    %CQIMCSCALIBRATIONDATASET Versioned non-normative calibration record.

    methods (Static)
        function value = validate(value)
            required = ["DatasetID","Version","ProfileKey","ConfidenceLevel", ...
                "TrainingSHA256","HoldoutError","DatasetSHA256","ThresholdDb"];
            for field = required
                if ~isfield(value,char(field))
                    error("RSLA:InvalidCalibrationProvenance", ...
                        "Calibration dataset is missing %s.",field);
                end
            end
            validHash = strlength(string(value.ProfileKey))==64 && ...
                strlength(string(value.TrainingSHA256))==64 && ...
                strlength(string(value.DatasetSHA256))==64;
            valid = strlength(string(value.DatasetID))>0 && ...
                strlength(string(value.Version))>0 && validHash && ...
                isfinite(double(value.ConfidenceLevel)) && ...
                double(value.ConfidenceLevel)>0 && ...
                double(value.ConfidenceLevel)<1 && ...
                isfinite(double(value.HoldoutError)) && ...
                isfinite(double(value.ThresholdDb));
            if ~valid
                error("RSLA:InvalidCalibrationProvenance", ...
                    "Calibration provenance, confidence, holdout or hash is invalid.");
            end
            value.Valid = true;
            value.NormativeClaim = "implementation_calibration_not_universal_3gpp_threshold";
        end
    end
end
