classdef ULChannelSoundingState
    %ULCHANNELSOUNDINGSTATE Immutable measured SRS scheduler authority.

    properties (SetAccess=immutable)
        Data struct
    end

    methods
        function obj = ULChannelSoundingState(data)
            required = ["MeasurementID","UEID","CellID","BWPID","ResourceID", ...
                "BeamID","ProducerSlot","AvailableSlot","ConfigurationEpoch", ...
                "ChannelEstimateSHA256","CovarianceSHA256","MeasuredRI", ...
                "MeasuredSRI","MeasuredTPMI","CalibrationValid","CovarianceValid"];
            for field = required
                if ~isfield(data,char(field))
                    error("RSLA:MissingMeasuredInput", ...
                        "UL sounding state is missing %s.",field);
                end
            end
            data.Source = "received_srs_samples";
            data.Valid = logical(data.CalibrationValid)&&logical(data.CovarianceValid);
            obj.Data = data;
        end

        function decision = consume(obj,consumer)
            measurement = obj.Data;
            measurement.Valid = obj.Data.Valid;
            validity = sixgr.phy.rsla.MeasurementValidityChecker.validate( ...
                measurement,consumer);
            if ~obj.Data.Valid
                error("RSLA:MissingMeasuredInput", ...
                    "SRS channel/covariance state is not calibrated and valid.");
            end
            selectedDigest = sixgr.phy.rsla.RSLAUtil.hash(struct( ...
                "RI",obj.Data.MeasuredRI,"SRI",obj.Data.MeasuredSRI, ...
                "TPMI",obj.Data.MeasuredTPMI, ...
                "Channel",obj.Data.ChannelEstimateSHA256, ...
                "Covariance",obj.Data.CovarianceSHA256));
            decision = struct("SelectedRI",obj.Data.MeasuredRI, ...
                "SelectedSRI",obj.Data.MeasuredSRI, ...
                "SelectedTPMI",obj.Data.MeasuredTPMI, ...
                "SelectedPrecoderSHA256",selectedDigest, ...
                "AppliedPrecoderSHA256",selectedDigest, ...
                "DecisionSource","SRS_MEASURED", ...
                "AgeSlots",validity.AgeSlots,"Valid",true);
        end
    end
end
