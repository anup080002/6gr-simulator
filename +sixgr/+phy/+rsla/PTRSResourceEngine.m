classdef PTRSResourceEngine
    %PTRSRESOURCEENGINE Bounded DL/UL PT-RS plan and measured CPE correction.

    methods (Static)
        function plan = planVector(row)
            direction = upper(sixgr.phy.rsla.RSLAUtil.text(row,"Direction",""));
            waveform = upper(sixgr.phy.rsla.RSLAUtil.text(row,"Waveform",""));
            timeDensity = sixgr.phy.rsla.RSLAUtil.number(row,"TimeDensity",NaN);
            frequencyDensity = sixgr.phy.rsla.RSLAUtil.number( ...
                row,"FrequencyDensity",NaN);
            reOffset = sixgr.phy.rsla.RSLAUtil.number(row,"REOffset",NaN);
            port = sixgr.phy.rsla.RSLAUtil.number(row,"AssociatedDMRSPort",NaN);
            valid = ismember(direction,["DL","UL"]) && ...
                ismember(waveform,["CP-OFDM","DFT-S-OFDM"]) && ...
                ~(direction=="DL" && waveform=="DFT-S-OFDM") && ...
                ismember(timeDensity,[1 2 4]) && ...
                ismember(frequencyDensity,[2 4]) && ...
                ismember(reOffset,0:3) && port>=0 && port<=3;
            if ~valid
                error("RSLA:InvalidPTRSConfiguration", ...
                    "Invalid PT-RS tuple for the bounded Release-18 profile.");
            end
            symbols = (0:timeDensity:13).';
            prbs = (0:frequencyDensity:51).';
            [symbolGrid,prbGrid] = ndgrid(symbols,prbs);
            subcarrier = mod(reOffset+port,12);
            linear = symbolGrid(:)*52*12+prbGrid(:)*12+subcarrier;
            sequence = exp(1j*pi/2*mod((0:numel(linear)-1).'+port,4));
            plan = struct("Direction",direction,"Waveform",waveform, ...
                "TimeDensity",timeDensity,"FrequencyDensity",frequencyDensity, ...
                "REOffset",reOffset,"AssociatedDMRSPort",port, ...
                "IndicesZeroBased",linear,"Symbols",sequence, ...
                "IndexSHA256",sixgr.phy.rsla.RSLAUtil.hash(linear), ...
                "SequenceSHA256",sixgr.phy.rsla.RSLAUtil.hash( ...
                    [real(sequence) imag(sequence)]));
        end

        function result = measureAndCorrect(plan,phaseProfile)
            severity = lower(string(phaseProfile));
            switch severity
                case "none"
                    phase = 0;
                case "low"
                    phase = 0.04;
                case "medium"
                    phase = 0.10;
                case "high"
                    phase = 0.20;
                case "pn-bounded"
                    phase = 0.12;
                otherwise
                    error("RSLA:UnsupportedPhaseNoiseProfile", ...
                        "Unsupported phase-noise profile: %s.",severity);
            end
            reference = plan.Symbols(:);
            received = reference.*exp(1j*phase);
            measuredCPE = angle(sum(received.*conj(reference)));
            corrected = received.*exp(-1j*measuredCPE);
            evmBefore = sixgr.phy.rsla.EVMMeasurementEngine.measure( ...
                received,reference,"equalized_reference_RE");
            evmAfter = sixgr.phy.rsla.EVMMeasurementEngine.measure( ...
                corrected,reference,"equalized_reference_RE");
            result = struct("CPEBeforeRad",phase, ...
                "EstimatedCPERad",measuredCPE, ...
                "CPEAfterRad",angle(sum(corrected.*conj(reference))), ...
                "EVMBeforePercent",evmBefore.Percent, ...
                "EVMAfterPercent",evmAfter.Percent, ...
                "CorrectionApplied",true, ...
                "EstimateSource","received_ptrs_samples", ...
                "AppliedResourceSHA256",plan.IndexSHA256);
        end
    end
end
