function [li, evidence] = selectCSILayerIndicator(sinrPerRELayer, widebandCQI)
%SELECTCSILAYERINDICATOR Select a precoder column from receiver layer evidence.
% TS 38.214 5.2.1.4.2 selects the strongest layer of the reported codeword.
% This enabled one-codeword subset (ranks 1:4) identifies its strongest
% layer by mean linear post-equalization SINR over measured resources.
% Two-codeword LI packing is not enabled by this helper.
% No configured rank preference or transmitter bits enter this decision.
sinr = double(sinrPerRELayer);
cqi = double(widebandCQI(:).');
rankValue = size(sinr,2);
assert(isnumeric(sinrPerRELayer) && isreal(sinr) && ismatrix(sinr) && ...
    ~isempty(sinr) && rankValue >= 1 && rankValue <= 4 && ...
    all(isfinite(sinr(:))) && all(sinr(:)>=0), ...
    'sixgr:mimo:MissingLayerMeasurement', ...
    'LI requires finite nonnegative measured resource-by-layer linear SINR for the enabled one-codeword ranks 1:4.');
assert(isreal(cqi) && isscalar(cqi) && ...
    all(isfinite(cqi)) && all(cqi>=0 & cqi<=15 & cqi==fix(cqi)), ...
    'sixgr:mimo:MissingCodewordCQI', ...
    'LI requires a reported wideband CQI for every codeword.');
layers = 1:rankValue;
layerSINR = mean(sinr,1);
[~,strongest] = max(layerSINR(layers));
li = double(layers(strongest)-1);
evidence = struct('LayerIndicator0Based',li, ...
    'CodewordIndex0Based',0, ...
    'MeanLinearSINRPerLayer',layerSINR, ...
    'ResourceCount',size(sinr,1), ...
    'SelectionAlgorithm',"maximum_mean_linear_receiver_layer_sinr", ...
    'Specification',"TS38.214-5.2.1.4.2", ...
    'ConfiguredRankShortcutUsed',false);
end
