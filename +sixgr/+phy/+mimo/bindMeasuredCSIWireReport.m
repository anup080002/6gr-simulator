function encoded = bindMeasuredCSIWireReport(reportConfig, record)
%BINDMEASUREDCSIWIREREPORT Preserve the UE's measured typed report bit-exactly.
% This is a UE-side adapter, not a gNB receive-layout or field authority.
% Structured Type-II PMI is recovered from its measured wire fields rather
% than replaced with a scalar PMI or reconstructed from lossy JSON arrays.
assert(isa(reportConfig,'sixgr.phy.mimo.CSIReportConfiguration'), ...
    'sixgr:mimo:MissingCSIReportConfig','An installed typed report is required.');
required={'CSIReportConfigID','CSIConfigurationEpoch','CSIUCIChannel', ...
    'CSIPart1BitsToken','CSIPart2BitsToken','RI','CQI','LI','CRI','PMI'};
assert(isstruct(record) && isscalar(record) && all(isfield(record,required)), ...
    'sixgr:mimo:MissingMeasuredCSIWireReport','Retain the measured report and its configuration identity.');
assert(string(record.CSIReportConfigID)==reportConfig.ReportConfigID && ...
    isequal(double(record.CSIConfigurationEpoch),reportConfig.Epoch) && ...
    upper(string(record.CSIUCIChannel))==reportConfig.UCIChannel, ...
    'sixgr:mimo:MeasuredCSIConfigurationMismatch', ...
    'Measured CSI belongs to a different report configuration, epoch, or transport.');
part1=sixgr.runtime.RawCSVArrayCodec.decode(record.CSIPart1BitsToken);
part2=sixgr.runtime.RawCSVArrayCodec.decode(record.CSIPart2BitsToken);
% Decode validates binary values before any integer conversion can hide a
% malformed fractional token. Part 1 determines the Type-II Part-2 length.
values=reportConfig.decode(part1,part2);
for pair={'RI','RI';'CQI','CQI_CW0';'LI','LI';'CRI','CRI';'PMI','PMI'}.'
    if isfield(values,pair{2})
        assert(isequal(double(record.(pair{1})),double(values.(pair{2}))), ...
            'sixgr:mimo:MeasuredCSIFieldMismatch', ...
            'Measured %s differs from the retained typed report.',pair{1});
    end
end
if lower(reportConfig.CodebookType)=="typeii"
    assert(isscalar(record.PMI) && isnan(record.PMI), ...
        'sixgr:mimo:MeasuredCSIFieldMismatch','Type-II has structured PMI, not a scalar index.');
end
encoded=reportConfig.build(values);
assert(isequal(double(encoded.Part1Bits(:)),double(part1(:))) && ...
    isequal(double(encoded.Part2Bits(:)),double(part2(:))), ...
    'sixgr:mimo:MeasuredCSIWireMismatch', ...
    'Binding measured CSI must not change any report bit.');
end
