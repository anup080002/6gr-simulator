classdef PortableTypeICSIReportEngine
    % Explicit portable implementation policy, not native MaxSE or decoded BLER.
    % Full measured channel snapshots and immutable disturbance are the operands.
    methods (Static)
        function csi = run(carrier,csirs,dmrs,H,nVar,cfg,measurement,options)
            arguments
                carrier (1,1) nrCarrierConfig
                csirs (1,1) nrCSIRSConfig
                dmrs (1,1) nrPDSCHDMRSConfig
                H {mustBeNumeric}
                nVar (1,1) double {mustBeNonnegative}
                cfg (1,1) struct
                measurement (1,1) sixgr.phy.mimo.CSIMeasurementState
                options.Direction (1,1) string = "DL"
            end
            localValidateInputs(carrier,csirs,H,cfg,measurement);
            disturbance=localMeasuredDisturbance(measurement,nVar,size(H,3),cfg);
            reportRequest = sixgr.util.structGet(cfg,"ReportConfiguration",[]);
            if isempty(reportRequest)
                error("sixgr:mimo:MissingCSIReportConfig", ...
                    "Strict NR CSI execution requires ReportConfiguration.");
            end
            [ri,rankDecision,W,pmi,pmiSet,pmiInfo,cqiValue,cqiInfo] = ...
                localPortableSelection(H,disturbance,cfg,measurement,reportRequest);
            rankDomain=double(cfg.RankDomain);
            cri=localMeasuredCRI(measurement,double(reportRequest.NumCSIResources));
            typedRequest=reportRequest; typedRequest.Rank=ri;
            matrixAuthority="ts38214_single_panel_formula_from_measured_pmi";
            typedConfig = sixgr.phy.mimo.CSIReportConfiguration( ...
                typedRequest,double(reportRequest.Epoch));
            [li,liEvidence]=sixgr.phy.mimo.selectCSILayerIndicator( ...
                pmiInfo.SINRPerREPMI,cqiValue);
            values = struct("CRI",cri,"RI",double(ri), ...
                "CQI_CW0",double(cqiValue(1)),"PMI",pmi.LinearIndex, ...
                "PMI_I11",pmi.i11,"PMI_I12",pmi.i12, ...
                "PMI_I13",pmi.i13,"PMI_I2",pmi.i2, ...
                "LI",li);
            typedReport = typedConfig.build(values);
            [singularValues,conditionNumberDB] = ...
                localMeasuredSpatialCondition(measurement.ChannelEstimate,ri);
            shannonDiagnostic = localSelectionObjective(pmiInfo);
            objective = rankDecision.SelectedObjective;
            % Original selected MMSE layer SINRs determine the receiver
            % aggregate. CQI separately applies the explicit authored model.
            layerSINR=double(pmiInfo.SINRPerREPMI);
            assert(~isempty(layerSINR) && all(isfinite(layerSINR(:))) && all(layerSINR(:)>=0), ...
                'sixgr:mimo:MissingLayerMeasurement','Selected-PMI receiver SINRs are invalid.');
            receiverSINR=10*log10(expm1(mean(log1p(layerSINR),'all')));
            cqiEffectiveSINR=double(cqiInfo.EffectiveSINR(1));
            csi = struct( ...
                "Direction",upper(options.Direction), ...
                "RI",double(ri),"PMI",pmi.LinearIndex, ...
                "PMI_i1",[pmi.i11 pmi.i12 pmi.i13], ...
                "PMI_i2",pmi.i2,"PMISet",pmiSet, ...
                "PMI_I11",pmi.i11,"PMI_I12",pmi.i12,"PMI_I13",pmi.i13,"PMI_I2",pmi.i2, ...
                "CQI",double(cqiValue(1)),"LI",li, ...
                "CRI",cri,"WidebandSINR_dB",receiverSINR, ...
                "CQIEffectiveSINR_dB",cqiEffectiveSINR, ...
                "CQIEffectiveSINRSource","configured_threshold_CQI_model_not_decoded_BLER", ...
                "ReceiverSINRAggregation","exp(mean(log(1+selected_PMI_layer_SINR)))-1", ...
                "Precoder_W",W, ...
                "PrecoderMatrixAuthority",matrixAuthority, ...
                "PrecoderMatrixSHA256",sixgr.phy.mimo.MatrixContract.digest(W), ...
                "ConditionNumber_dB",conditionNumberDB, ...
                "SingularValues",singularValues, ...
                "RankCandidateObjective",rankDecision.ObjectiveByRank, ...
                "RankSelectionEvidence",rankDecision, ...
                "RankDomain",rankDomain, ...
                "RankDecisionReason","portable_measured_channel_MMSE_mutual_information_policy", ...
                "RuntimeEvidenceSource", ...
                    "measured_csirs_portable_TypeI_MMSE_configured_CQI", ...
                "MeasurementID",measurement.MeasurementID, ...
                "MeasurementResourceID",measurement.ResourceID, ...
                "MeasurementResourceOrdinal",measurement.ResourceOrdinal, ...
                "MeasurementSlot",measurement.Slot, ...
                "MeasurementProvenance",measurement.Provenance, ...
                "DisturbanceCovarianceUsed",disturbance, ...
                "InterferenceCovarianceUsed",~isempty(measurement.InterferenceCovariance), ...
                "ConfiguredOracleUsed",false, ...
                "ChannelStateInformationMode",typedConfig.ReportQuantity, ...
                "CSIReportConfiguration",typedConfig, ...
                "TypedReport",typedReport, ...
                "CSIPart1Bits",typedReport.Part1Bits, ...
                "CSIPart2Bits",typedReport.Part2Bits, ...
                "CSIPayloadBitLength",numel(typedReport.Part1Bits)+numel(typedReport.Part2Bits), ...
                "CustomContainerUsed",false, ...
                "ConfiguredSNRUsed",false, ...
                "SVDThresholdUsed",false, ...
                "SelectionInfo",struct( ...
                    "LayerIndicatorEvidence",liEvidence, ...
                    "SelectedSINRPerRELayer",pmiInfo.SINRPerREPMI, ...
                    "SelectedMetric",objective, ...
                    "SelectedMetricDefinition",rankDecision.ObjectiveDefinition, ...
                    "RankSelectionEvidence",rankDecision, ...
                    "FinalReportShannonDiagnostic_bpsHz",shannonDiagnostic, ...
                    "FinalReportShannonDiagnosticUsedForRankSelection",true, ...
                    "SelectedRank",double(ri), ...
                    "SelectedPMI",pmi.LinearIndex, ...
                    "PMISet",pmiSet, ...
                    "MatrixSHA256",sixgr.phy.mimo.MatrixContract.digest(W), ...
                    "Specification","TS38.214_TypeI_codebook_implementation_selection_policy", ...
                    "SelectionPolicyClassification","IMPLEMENTATION_POLICY", ...
                    "IndependentSelectionQualityVerified",false, ...
                    "ExecutionEngine","sixgr_PortableTypeICSIReportEngine", ...
                    "ConfiguredSNRUsed",false,"SVDThresholdUsed",false));
            csi.CQIModelEvidence=rankDecision.CQIModelEvidence;
        end
    end
end

function R=localMeasuredDisturbance(measurement,nVar,nRx,cfg)
measuredNoise=measurement.NoiseVariance;
assert(isnumeric(measuredNoise) && isreal(measuredNoise) && isscalar(measuredNoise) && ...
    isfinite(measuredNoise) && measuredNoise>=0 && isfinite(nVar) && ...
    abs(nVar-double(measuredNoise))<=1e-12*max([realmin,nVar,double(measuredNoise)]), ...
    'sixgr:mimo:MeasurementIdentityMismatch', ...
    'CSI selection noise must match the immutable CSI measurement.');
R=measurement.InterferenceCovariance;
if isempty(R)
    R=nVar; % Scalar measured noise; expanded to receiver covariance at selection.
    return;
end
includesNoise=measurement.InterferenceCovarianceIncludesNoise;
if isa(R,'sixgr.phy.mimo.InterferenceCovarianceState')
    R.validateAt(double(sixgr.util.structGet(cfg,'CurrentSlot',measurement.Slot)));
    includesNoise=R.IncludesNoise;
    R=R.Matrix;
end
assert(isnumeric(R) && isequal(size(R),[nRx nRx]) && all(isfinite(R(:))) && ...
    norm(R-R','fro')<=1e-12*max(norm(R,'fro'),realmin), ...
    'sixgr:mimo:InvalidInterferenceCovariance', ...
    'Measured CSI covariance must be finite Hermitian Nrx-by-Nrx.');
R=double(R);
assert(min(real(eig(R)))>=-1e-12*max(norm(R,'fro'),realmin), ...
    'sixgr:mimo:InvalidInterferenceCovariance','Measured CSI covariance must be positive semidefinite.');
if ~includesNoise, R=R+nVar*eye(nRx); end
[~,notPositiveDefinite]=chol(R);
assert(notPositiveDefinite==0,'sixgr:mimo:InvalidInterferenceCovariance', ...
    'CSI receiver disturbance covariance must be positive definite.');
end

function localValidateInputs(carrier,csirs,H,cfg,measurement)
% High-port reporting must obey the same causal measurement lifetime as
% the two-port engine. A retained Hest is not fresh merely because its
% dimensions still match the configured CSI-RS resource.
measurement.validateAt(double(sixgr.util.structGet(cfg,"CurrentSlot",measurement.Slot)));
if isempty(H) || ndims(H) ~= 4 || ...
        size(H,1) ~= 12*double(carrier.NSizeGrid) || ...
        size(H,2) ~= double(carrier.SymbolsPerSlot) || ...
        size(H,4) ~= double(max(csirs.NumCSIRSPorts)) || ...
        any(~isfinite(real(H(:))) | ~isfinite(imag(H(:))))
    error("sixgr:mimo:MissingMeasurementState", ...
        "Strict NR CSI requires finite K-by-L-by-Nrx-by-P runtime CSI-RS Hest.");
end
if size(H,4) ~= size(measurement.ChannelEstimate,2)
    error("sixgr:mimo:MeasurementIdentityMismatch", ...
        "Full CSI-RS Hest and immutable wideband measurement have different port counts.");
end
if ~logical(sixgr.util.structGet(cfg,"Strict",false))
    error("sixgr:mimo:StrictModeRequired", ...
        "PortableTypeICSIReportEngine is reserved for strict runtime CSI evidence.");
end
end

function cri = localMeasuredCRI(measurement,numResources)
cri = double(measurement.ResourceOrdinal);
if ~(isscalar(cri) && isfinite(cri) && cri >= 0 && ...
        cri == round(cri) && cri < numResources)
    error("sixgr:mimo:BeamReportMismatch", ...
        "Measured CRI %g is outside [0,%d].",cri,numResources-1);
end
end

function [singularValues,conditionNumberDB] = localMeasuredSpatialCondition(H,rankValue)
H = double(H);
if ismatrix(H)
    covariance = H' * H;
else
    covariance = complex(zeros(size(H,2)));
    for k = 1:size(H,3)
        covariance = covariance + H(:,:,k)'*H(:,:,k);
    end
    covariance = covariance/max(1,size(H,3));
end
singularValues = sqrt(max(sort(real(eig((covariance+covariance')/2)),"descend"),0));
if numel(singularValues) >= rankValue && singularValues(rankValue) > 0
    conditionNumberDB = 20*log10(singularValues(1)/singularValues(rankValue));
else
    conditionNumberDB = Inf;
end
end

function objective = localSelectionObjective(info)
sinr = double(sixgr.util.structGet(info,"SINRPerSubbandPMI",[]));
if isempty(sinr) || any(~isfinite(sinr(:))) || any(sinr(:) < 0)
    error("sixgr:mimo:MissingMeasurementState", ...
        "Portable selected-PMI objective requires finite measured layer SINRs.");
end
objective = mean(sum(log2(1+sinr),2),"omitnan");
end

function [ri,d,W,pmi,pmiSet,info,cqi,cqiInfo]=localPortableSelection(H,R,cfg,m,request)
id='sixgr:mimo:UnsupportedPortableCSI';
assert(request.Ports==4 && lower(string(request.CodebookType))=="typei-singlepanel" && ...
    lower(string(request.FrequencyGranularity))=="wideband" && ...
    upper(string(cfg.Receiver))=="MMSE",id, ...
    'Portable v1 supports four-port wideband Type-I SinglePanel and explicit MMSE only.');
ranks=double(cfg.RankDomain(:).');
assert(~isempty(ranks)&&all(ismember(ranks,1:min(4,size(H,3))))&& ...
    isequal(ranks,unique(ranks)),id,'Rank domain must be ascending, unique and realizable.');
model=cfg.PortableCQIModel;
assert(isstruct(model)&&all(isfield(model,{'ModelID','Source','ThresholdsDB','ComparisonToleranceDB','CQITable'}))&& ...
    strlength(string(model.ModelID))>0 && string(model.CQITable)==string(cfg.CQITable) && ...
    numel(model.ThresholdsDB)==15 && all(isfinite(model.ThresholdsDB)) && ...
    all(diff(model.ThresholdsDB)>0),id,'An explicit 15-threshold CQI model is required.');
X=reshape(permute(H,[3 4 1 2]),size(H,3),size(H,4),[]);
if isscalar(R), R=R*eye(size(H,3)); end
assert(all(isfinite(R(:)))&&min(real(eig(R)))>0,id,'Positive measured disturbance is required.');
objectives=zeros(size(ranks)); candidates=cell(size(ranks)); matrices=cell(size(ranks));
for k=1:numel(ranks)
    q=request; q.Rank=ranks(k);
    pack=sixgr.phy.mimo.CodebookEngine.enumerate(q);
    [matrices{k},selected]=sixgr.phy.mimo.CodebookEngine.select(X,pack.Matrices, ...
        'InterferenceCovariance',R,'InterferenceCovarianceIncludesNoise',true, ...
        'Receiver','MMSE','Objective','posteq_mutual_information');
    selected.PMI=double(pack.CandidateIndices(selected.SelectedIndex+1));
    selected.CandidateIndices=pack.CandidateIndices;
    selected.CandidateMatrixSHA256=pack.MatrixSHA256;
    candidates{k}=selected; objectives(k)=selected.SelectedMetric;
end
[objective,j]=max(objectives); ri=ranks(j); selected=candidates{j}; W=matrices{j};
q=request; q.Rank=ri;
[expected,components]=sixgr.phy.mimo.TypeISinglePanelCodebook.matrix(q,selected.PMI);
assert(isequal(W,expected),'sixgr:mimo:PrecoderAuthorityMismatch','Exact selected codebook coefficients changed.');
pmi=struct('i11',components.PMI_I11,'i12',components.PMI_I12, ...
    'i13',components.PMI_I13,'i2',components.PMI_I2,'LinearIndex',selected.PMI);
pmiSet=struct('i1',[pmi.i11 pmi.i12 pmi.i13],'i2',pmi.i2);
layer=selected.SelectedSINRPerRELayer;
effective=10*log10(expm1(mean(log1p(layer),'all')));
if isinf(effective)&&effective<0
    % Exactly zero measured channel energy is an outage, not fabricated finite SINR.
    cqi=0; mapping=struct('EffectiveSINRdB',effective,'CQI',0,'Reason',"zero_measured_layer_SINR");
else
    [cqi,mapping]=sixgr.link.resolveCQIFromConfiguredThresholds(effective, ...
        double(model.ThresholdsDB(:).'),double(model.ComparisonToleranceDB));
end
mapping.ModelID=string(model.ModelID); mapping.CQITable=string(model.CQITable);
mapping.Source="explicit_configured_threshold_model"; mapping.AuthoredSource=string(model.Source);
mapping.ThresholdsDB=double(model.ThresholdsDB); mapping.ComparisonToleranceDB=double(model.ComparisonToleranceDB);
mapping.CalibrationQualified=false;
info=struct('SINRPerREPMI',layer,'SINRPerSubbandPMI',layer);
cqiInfo=struct('EffectiveSINR',effective);
for k=1:numel(candidates)
    candidates{k}=rmfield(candidates{k},'SelectedSINRPerRELayer');
end
d=struct('ContractVersion',"sixgr.portable_TypeI_MMSE_rank_decision/v1", ...
    'Source',"original_measured_H_portable_MMSE_candidates",'MATLABRelease',string(version('-release')), ...
    'RankDomain',ranks,'ObjectiveByRank',objectives,'SelectedRank',ri,'SelectedObjective',objective, ...
    'TiePolicy',"first_sorted_rank_then_first_candidate", ...
    'ObjectiveDefinition',"mean_snapshots_sum_layers_log2_one_plus_MMSE_SINR", ...
    'Classification',"IMPLEMENTATION_POLICY",'ReferencePlane',"received_channel_and_measured_disturbance", ...
    'ChannelSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(H), ...
    'DisturbanceSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(R), ...
    'Configuration',struct('ReportConfiguration',request,'RankDomain',ranks, ...
        'Receiver',string(cfg.Receiver),'Strict',true,'CurrentSlot',double(cfg.CurrentSlot), ...
        'CQITable',string(cfg.CQITable),'PortableCQIModel',model),'Candidates',{candidates},'AdditionalRankSearches',0,'RankSearchCallCount',1,'DecodedBLERAvailable',false, ...
    'IndependentSelectionQualityVerified',false,'StandardizedAccuracyQualified',false, ...
    'MeasurementID',m.MeasurementID,'MeasurementDigest',m.Digest,'MeasurementSlot',m.Slot, ...
    'ReportConfigID',string(request.ReportConfigID),'ReportConfigurationEpoch',double(request.Epoch), ...
    'SelectedPMI',selected.PMI,'SelectedMatrixSHA256',sixgr.phy.mimo.MatrixContract.digest(W), ...
    'CQIModelEvidence',mapping);
end
