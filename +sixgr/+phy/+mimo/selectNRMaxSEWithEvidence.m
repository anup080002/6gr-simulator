function [ri,evidence]=selectNRMaxSEWithEvidence(carrier,csirs,report,H,disturbance,ranks)
% Retain the actual R2026a MaxSE decision operands, not a Shannon proxy.
% Native per-rank CQI/PMI selection still owns its channel/noise processing.
% The objective uses MODEL-estimated transport BLER, not decoded TB outcomes.
% No truth channel, second rank search, RF execution or receiver feedback is
% introduced. This is a release-pinned implementation policy, not an NR
% prescribed rank-selection algorithm or independent accuracy reference.
arguments
    carrier (1,1) nrCarrierConfig
    csirs (1,1) nrCSIRSConfig
    report (1,1) nrCSIReportConfig
    H {mustBeNumeric}
    disturbance {mustBeNumeric}
    ranks (1,:) double
end
id='sixgr:mimo:MaxSEEvidenceConfiguration';
assert(string(version('-release'))=="2026a",id,'This adapter is pinned to R2026a.');
assert(any(strcmpi(report.CodebookType,{'type1SinglePanel','type2'})),id, ...
    'Only the existing strict Type-I single-panel and Type-II domains are supported.');
limit=min([size(H,3),size(H,4),8]);
if strcmpi(report.CodebookType,'type2'), limit=min(limit,2); end
allowed=find(report.RIRestriction);
if isempty(report.RIRestriction), allowed=1:limit; end
assert(~isempty(ranks)&&isequal(unique(ranks),reshape(allowed,1,[]))&& ...
    all(isfinite(ranks)&ranks==fix(ranks)),id,'Requested ranks must identify the installed RI restriction.');
requestedRanks=ranks;
ranks=reshape(intersect(allowed,1:limit),1,[]);
assert(~isempty(ranks),id,'No admissible rank within the physical receive/port dimensions.');
assert(~isempty(nrCSIRSIndices(carrier,csirs)),id,'No rank search without a current CSI-RS occasion.');
% R2026a accepts table4-r17 in nrCSIReportConfig, but its installed internal
% CQI selection table helper implements only tables 1/2/3. This is a backend
% limitation, NOT an invalid NR table. Do not substitute another table or
% continue with an undefined native table variable (retained v167 failure).
tableName=lower(string(report.CQITable));
assert(~ismember(tableName,["table4","table4-r17"]), ...
    'sixgr:mimo:NativeCQITableUnsupported', ...
    'R2026a native CQI selection does not implement table4-r17; no substitute table is permitted.');
tableNumber=find(strcmpi(tableName,["table1","table2","table3"]));
assert(isscalar(tableNumber),id,'Retain the configured NR CQI table.');
tables=nrCQITables;
tableData=tables.("CQITable"+tableNumber);
scores=nan(max(ranks),1); candidates=cell(1,numel(ranks));
for ordinal=1:numel(ranks)
    rankValue=ranks(ordinal);
    [cqi,pmi,cqiInfo,pmiInfo]=nr5g.internal.nrCQISelect( ...
        carrier,csirs,report,rankValue,H,disturbance);
    wideband=cqi(1,:); estimatedBLER=cqiInfo.TransportBLER(1,:);
    ncw=numel(wideband); layers=floor((rankValue+(0:ncw-1))/ncw);
    assert(isequal(size(wideband),size(estimatedBLER))&& ...
        all(isnan(wideband)|(isfinite(wideband)&wideband==fix(wideband)&wideband>=0&wideband<=15)), ...
        'sixgr:mimo:MaxSEEvidenceOperands','Native CQI and estimated BLER populations must match.');
    efficiency=nan(size(wideband)); status="native_CQI_unavailable";
    if any(wideband==0)
        % Preserve native out-of-range handling and deterministic ties.
        scores(rankValue)=0; status="native_out_of_range_CQI_zero_objective";
    elseif all(~isnan(wideband))
        assert(all(isfinite(estimatedBLER)&estimatedBLER>=0&estimatedBLER<=1), ...
            'sixgr:mimo:MaxSEEvidenceOperands','Native estimated block error probabilities are invalid.');
        spectral=tableData.SpectralEfficiency(wideband+1);
        efficiency=reshape(spectral,size(wideband));
        scores(rankValue)=(layers.*(1-estimatedBLER))*spectral;
        status="native_model_objective_available_not_decoded_BLER";
    end
    candidates{ordinal}=struct('Rank',rankValue,'WidebandCQI',wideband, ...
        'ModelEstimatedTransportBLER',estimatedBLER,'CodewordLayerCounts',layers, ...
        'CQITableSpectralEfficiency',efficiency,'Objective',scores(rankValue), ...
        'Status',status,'RankSearchPMI',pmi, ...
        'RankSearchPrecoderSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(pmiInfo.W));
end
[best,ri]=max(scores);
assert(isfinite(best)&&ismember(ri,ranks),'sixgr:mimo:MaxSEEvidenceUnavailable', ...
    'The native model has no available admissible rank; do not invent a recommendation.');
configuration=struct();
for field=["NStartBWP","NSizeBWP","CQITable","CodebookType","PanelDimensions", ...
        "CodebookMode","CQIFormatIndicator","PMIFormatIndicator","RIRestriction", ...
        "CodebookSubsetRestriction","I2Restriction","NumberOfBeams","PhaseAlphabetSize", ...
        "SubbandAmplitude","SubbandSize","PRGBundleSize"]
    configuration.(field)=report.(field);
end
evidence=struct('ContractVersion',"sixgr.native_MaxSE_rank_decision/v1", ...
    'Source',"original_nr5g_nrCQISelect_per_admissible_rank", ...
    'MATLABRelease',string(version('-release')),'RankDomain',ranks, ...
    'RequestedRankDomain',requestedRanks, ...
    'ObjectiveByRank',scores,'SelectedRank',ri,'SelectedObjective',best, ...
    'TiePolicy',"first_rank_returned_by_MATLAB_max", ...
    'ObjectiveDefinition',"sum_codewords_layers_times_one_minus_model_BLER_times_CQI_spectral_efficiency", ...
    'Classification',"MATLAB_BEHAVIOR_IMPLEMENTATION_POLICY", ...
    'ReferencePlane',"native_CQI_selection_model_on_supplied_received_channel_and_disturbance", ...
    'ChannelSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(H), ...
    'DisturbanceSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(disturbance), ...
    'Configuration',configuration,'Candidates',{candidates}, ...
    'RankSearchCallCount',numel(ranks),'AdditionalRankSearches',0, ...
    'DecodedBLERAvailable',false,'IndependentSelectionQualityVerified',false, ...
    'StandardizedAccuracyQualified',false);
end
