function validated = validatePeriodicPUCCHCSITiming(cfg)
%VALIDATEPERIODICPUCCHCSITIMING Validate the installed periodic PUCCH calendar.
% TS 38.331 V18.8.0 6.3.2, CSI-ReportConfig (p756) and
% CSI-ReportPeriodicityAndOffset (p764). These are NR values, not tunable
% scheduler policy. Period/offset are slots on the configured UL BWP clock
% (TS 38.214 V18.8.0 5.2.1.1); this helper does not convert numerologies.
% A PUCCH-configured report multiplexed onto PUSCH retains this calendar.
% Disabled, nonperiodic and independently PUSCH-configured reporting are
% outside this narrow validator; returning false does not qualify them.
arguments
    cfg (1,1) struct
end
validated=false;
enabled=sixgr.util.structGet(cfg,'phy.csi.reportCSI',false);
assert((islogical(enabled)||isnumeric(enabled)) && isreal(enabled) && ...
    isscalar(enabled) && isfinite(enabled) && any(enabled==[0 1]), ...
    'sixgr:mimo:InvalidCSIReportingEnablement','phy.csi.reportCSI must be explicitly binary.');
if ~enabled, return; end
trigger=sixgr.util.structGet(cfg,'phy.csi.reportTrigger',"");
assert((isstring(trigger) && isscalar(trigger) && ~ismissing(trigger)) || ...
    (ischar(trigger) && isrow(trigger)), ...
    'sixgr:mimo:InvalidCSIReportingTrigger','CSI report trigger must be original scalar text.');
trigger=lower(strtrim(string(trigger)));
assert(any(trigger==["periodic","semi_persistent","aperiodic"]), ...
    'sixgr:mimo:InvalidCSIReportingTrigger', ...
    'CSI report trigger must be periodic, semi_persistent or aperiodic.');
if trigger~="periodic", return; end
request=sixgr.util.structGet(cfg,'phy.csi.reportConfiguration',struct());
transport=sixgr.util.structGet(request,'ConfiguredUCIChannel', ...
    sixgr.util.structGet(request,'UCIChannel',""));
assert(((isstring(transport) && isscalar(transport) && ~ismissing(transport)) || ...
    (ischar(transport) && isrow(transport))) && ...
    any(upper(strtrim(string(transport)))==["PUCCH","PUSCH"]), ...
    'sixgr:mimo:MissingCSIConfiguredTransport', ...
    'Periodic CSI validation requires its original configured UCI transport.');
if upper(strtrim(string(transport)))~="PUCCH", return; end
period=sixgr.util.structGet(cfg,'phy.csi.reportPeriodicitySlots',NaN);
offset=sixgr.util.structGet(cfg,'phy.csi.reportOffsetSlots',NaN);
integer=@(x)isnumeric(x) && ~islogical(x) && isreal(x) && ...
    isscalar(x) && isfinite(x) && x==fix(x);
assert(integer(period) && ismember(double(period),[4 5 8 10 16 20 40 80 160 320]), ...
    'sixgr:mimo:InvalidPeriodicPUCCHCSIPeriod', ...
    ['phy.csi.reportPeriodicitySlots must be one of 4,5,8,10,16,20,40,80,160,320 ' ...
     'for a periodic PUCCH-configured CSI report (TS 38.331 V18.8.0 6.3.2).']);
assert(integer(offset) && offset>=0 && offset<period, ...
    'sixgr:mimo:InvalidPeriodicPUCCHCSIOffset', ...
    'phy.csi.reportOffsetSlots must be an integer from zero to period minus one.');
validated=true;
end
