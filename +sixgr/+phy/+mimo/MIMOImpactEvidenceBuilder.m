classdef MIMOImpactEvidenceBuilder
    %MIMOIMPACTEVIDENCEBUILDER Build executed paired Phase-07 evidence.

    methods (Static)
        function [tables, summary, records] = build( ...
                matrixPath, vectorRoot, cfg, runID, seedList, confidence)
            matrix = localReadStrings(matrixPath);
            families = localReadStrings(fullfile(vectorRoot, ...
                "mimo_impact_analysis_families.csv"));
            rules = localReadStrings(fullfile(vectorRoot, ...
                "mimo_impact_acceptance_rules.csv"));
            contract = localReadStrings(fullfile(vectorRoot, ...
                "desired_mimo_impact_csv_contract.csv"));
            localValidateMatrix(matrix,families,seedList);

            records = repmat(localEmptyRecord(),height(matrix),1);
            for index=1:height(matrix)
                records(index)=sixgr.phy.mimo. ...
                    MIMOImpactExperimentExecutor.execute(matrix(index,:),cfg);
            end

            tables=struct();
            tables.mimo_impact_raw_trials=localRaw( ...
                records,contract,runID,cfg);
            tables.mimo_impact_operating_points=localOperating( ...
                records,contract,runID,confidence,cfg);
            tables.mimo_impact_pairwise_effects=localEffects( ...
                records,contract,runID,cfg);
            tables.mimo_impact_rule_evaluation=localRules( ...
                rules,records,tables.mimo_impact_pairwise_effects, ...
                contract,runID,cfg);
            tables.mimo_impact_codebook_ri_pmi=localCodebook( ...
                records,contract,runID,cfg);
            tables.mimo_impact_csi_feedback=localCSI( ...
                records,contract,runID,cfg);
            tables.mimo_impact_high_rank=localHighRank( ...
                records,contract,runID,cfg);
            tables.mimo_impact_covariance_receiver=localCovariance( ...
                records,contract,runID,cfg);
            tables.mimo_impact_srs_ul=localSRS( ...
                records,contract,runID,cfg);
            tables.mimo_impact_mu_mimo=localMU( ...
                records,contract,runID,cfg);
            tables.mimo_impact_multitrp=localMultiTRP( ...
                records,contract,runID,cfg);
            tables.mimo_impact_hybrid=localHybrid( ...
                records,contract,runID,cfg);
            tables.mimo_impact_beam_management=localBeam( ...
                records,contract,runID,cfg);
            tables.mimo_impact_summary=localSummary( ...
                families,records,tables.mimo_impact_rule_evaluation, ...
                contract,runID,cfg);
            tables.mimo_impact_run_manifest=localManifest( ...
                matrixPath,records,contract,runID,seedList,confidence,cfg);

            summary=struct( ...
                "ExperimentCount",numel(records), ...
                "PairCount",height(tables.mimo_impact_pairwise_effects), ...
                "RuleCount",height(tables.mimo_impact_rule_evaluation), ...
                "IncompleteCount",sum(~[records.InvariantPassed]), ...
                "ExecutionBackend",string(cfg.evidence.execution_backend), ...
                "ApproximationMode",string(cfg.evidence.approximation_mode), ...
                "TruthQualified",logical(cfg.evidence.truth_qualified));
        end
    end
end

function localValidateMatrix(matrix,families,seedList)
required=["ExperimentID","FamilyID","PairID","Variant","FactorName", ...
    "FactorValue","Seed","PayloadID","ChannelRealizationID", ...
    "NoiseRealizationID","Profile","Channel","SNR_dB","TrialsTarget", ...
    "MinimumErrors","ConfidenceLevel","ExpectedStatus"];
if ~all(ismember(required,string(matrix.Properties.VariableNames)))
    error("sixgr:mimo:ImpactMatrixInvalid", ...
        "Impact matrix is missing mandatory columns.");
end
if height(matrix)~=768 || numel(unique(matrix.ExperimentID))~=768
    error("sixgr:mimo:ImpactMatrixInvalid", ...
        "Impact matrix requires 768 unique experiment rows.");
end
if height(families)~=64 || numel(unique(families.FamilyID))~=64
    error("sixgr:mimo:ImpactMatrixInvalid", ...
        "Impact family catalog requires 64 unique families.");
end
if any(~ismember(str2double(matrix.Seed),double(seedList(:))))
    error("sixgr:mimo:ImpactSeedMismatch", ...
        "SeedList does not cover every immutable experiment row.");
end
pairs=unique(matrix.PairID,"stable");
if numel(pairs)~=384
    error("sixgr:mimo:ImpactPairingInvalid", ...
        "Impact matrix requires 384 matched pairs.");
end
for pair=pairs.'
    rows=matrix(matrix.PairID==pair,:);
    if height(rows)~=2 || ...
            ~isequal(sort(lower(rows.Variant)),["baseline";"treatment"])
        error("sixgr:mimo:ImpactPairingInvalid", ...
            "Pair %s must contain one baseline and one treatment.",pair);
    end
    same=["FamilyID","Seed","PayloadID","ChannelRealizationID", ...
        "NoiseRealizationID","Profile","Channel","SNR_dB","TrialsTarget"];
    for name=same
        if numel(unique(rows.(name)))~=1
            error("sixgr:mimo:ImpactPairingInvalid", ...
                "Pair %s differs in controlled field %s.",pair,name);
        end
    end
end
end

