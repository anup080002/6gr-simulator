function value=localSummary(families,records,rules,contract,runID,cfg)
value=localTable(contract,"mimo_impact_summary.csv",height(families));
for i=1:height(families)
    family=families.FamilyID(i);
    selected=records(string({records.FamilyID})==family);
    pairCount=numel(unique(string({selected.PairID})));
    familyRules=rules(rules.FamilyID==family,:);
    hard=familyRules(familyRules.Severity=="HARD",:);
    statistical=familyRules(familyRules.Severity=="STATISTICAL",:);
    hardFailed=sum(lower(hard.Passed)~="true");
    inconclusive=0;
    if ~isempty(statistical)
        inconclusive=sum(lower(statistical.Passed)~="true");
    end
    blocked=sum(~[selected.InvariantPassed]);
    value=localAssign(value,i,struct("RunID",runID, ...
        "FamilyID",family,"ExperimentsExpected",12, ...
        "ExperimentsExecuted",numel(selected),"PairsExpected",6, ...
        "PairsComplete",pairCount,"HardRulesFailed",hardFailed, ...
        "StatisticalRulesInconclusive",inconclusive, ...
        "BlockedCount",blocked,"Status", ...
        localStatus(numel(selected)==12&&pairCount==6&& ...
        hardFailed==0&&blocked==0)));
end
value=localAddProvenance(value,cfg);
end

function value=localManifest(matrixPath,records,contract,runID,seeds,confidence,cfg)
value=localTable(contract,"mimo_impact_run_manifest.csv",1);
[~,gitCommit]=system("git rev-parse HEAD");
gitCommit=strtrim(string(gitCommit));
toolboxes=ver;
toolboxVersion=strjoin(string({toolboxes.Name})+"="+ ...
