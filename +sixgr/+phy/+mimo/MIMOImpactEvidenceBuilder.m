        "BLER",failures/r.Trials,"BLERCILower",low, ...
        "BLERCIUpper",high, ...
        "MeanSINRDB",mean(r.PerTrialSINRDB,"omitnan"), ...
        "MeanEVMPercent",mean(r.PerTrialEVMPercent,"omitnan"), ...
        "MeanGoodputMbps",mean(r.PerTrialGoodputMbps,"omitnan"), ...
