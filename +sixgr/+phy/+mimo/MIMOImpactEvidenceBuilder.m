function [low,high]=localWilson(events,trials,confidence)
if trials<=0, low=NaN; high=NaN; return; end
z=-sqrt(2)*erfcinv(2*(.5+confidence/2));
p=events/trials;
denominator=1+z^2/trials;
center=(p+z^2/(2*trials))/denominator;
half=z*sqrt(p*(1-p)/trials+z^2/(4*trials^2))/denominator;
low=max(0,center-half); high=min(1,center+half);
end

function [low,high]=localPairedBootstrap(differences,replicates,seed)
differences=double(differences(:));
n=numel(differences);
prior=rng; cleanup=onCleanup(@()rng(prior)); %#ok<NASGU>
rng(seed,"twister");
means=zeros(replicates,1);
for b=1:replicates
    indices=randi(n,n,1);
    means(b)=mean(differences(indices));
end
means=sort(means);
low=means(max(1,ceil(.025*replicates)));
high=means(min(replicates,floor(.975*replicates)));
end

function p=localMcNemar(baselineError,treatmentError)
b=sum(~baselineError & treatmentError);
c=sum(baselineError & ~treatmentError);
n=b+c;
if n==0, p=1; return; end
k=min(b,c);
p=min(1,2*betainc(.5,n-k,k+1));
end

function adjusted=localHolm(p)
[sorted,order]=sort(double(p(:)));
m=numel(sorted);
candidate=zeros(m,1);
running=0;
for i=1:m
    running=max(running,(m-i+1)*sorted(i));
    candidate(i)=min(1,running);
end
adjusted=zeros(m,1);
adjusted(order)=candidate;
end

function conclusion=localConclusion(low,high,margin,correctnessGate)
if correctnessGate, conclusion="correctness_gate";
elseif low>margin, conclusion="beneficial";
elseif high<-margin, conclusion="harmful";
elseif low>=-margin && high<=margin, conclusion="equivalent";
else, conclusion="inconclusive";
end
end

