end

function value=localEffects(records,contract,runID,cfg)
pairIDs=unique(string({records.PairID}),"stable");
n=numel(pairIDs);
value=localTable(contract,"mimo_impact_pairwise_effects.csv",n);
value.EffectScale=strings(n,1);
value.StandardizedCILower=strings(n,1);
value.StandardizedCIUpper=strings(n,1);
rawP=zeros(n,1);
for index=1:n
    selected=records(string({records.PairID})==pairIDs(index));
    baseline=selected(string({selected.Variant})=="baseline");
    treatment=selected(string({selected.Variant})=="treatment");
    b=mean(baseline.PerTrialGoodputMbps);
    t=mean(treatment.PerTrialGoodputMbps);
    effect=t-b;
    differences=treatment.PerTrialGoodputMbps- ...
        baseline.PerTrialGoodputMbps;
    [low,high]=localPairedBootstrap(differences, ...
        double(cfg.statistics.bootstrap_replicates), ...
        localPairBootstrapSeed(pairIDs(index)));
    p=localMcNemar(baseline.BlockErrors,treatment.BlockErrors);
    rawP(index)=p;
    margin=double(cfg.statistics.practical_margin_goodput_mbps);
    correctnessGate=any(str2double(extractAfter( ...
        baseline.FamilyID,"F"))==[29 34 44 45 56 57 58 59 60]);
    conclusion=localConclusion(low,high,margin,correctnessGate);
    scale=max([std(differences),abs(b),abs(t), ...
        double(cfg.statistics.practical_margin_goodput_mbps),eps]);
    value=localAssign(value,index,struct( ...
        "RunID",runID,"FamilyID",baseline.FamilyID, ...
        "PairID",pairIDs(index),"Metric","GoodputMbps", ...
        "BaselineValue",b,"TreatmentValue",t, ...
        "AbsoluteEffect",effect, ...
        "RelativeEffect",effect/max(abs(b),eps), ...
        "CILower",low,"CIUpper",high,"PValue",p, ...
        "AdjustedPValue",p,"EffectSize",effect/scale, ...
        "EffectScale",scale,"StandardizedCILower",low/scale, ...
        "StandardizedCIUpper",high/scale, ...
        "PracticalMargin",margin,"Conclusion",conclusion, ...
        "Status",localStatus(baseline.InvariantPassed && ...
        treatment.InvariantPassed)));
end
families=unique(value.FamilyID,"stable");
for family=families.'
    rows=find(value.FamilyID==family);
    value.AdjustedPValue(rows)=string(compose("%.17g", ...
        localHolm(rawP(rows))));
end
end

function value=localRules(rules,records,effects,contract,runID,cfg)
n=height(rules);
value=localTable(contract,"mimo_impact_rule_evaluation.csv",n);
for index=1:n
    family=rules.FamilyID(index);
    selected=records(string({records.FamilyID})==family);
    severity=upper(rules.Severity(index));
    if severity=="HARD"
        observed=sum([selected.InvariantPassed]);
        threshold="12_executed_invariants";
        passed=numel(selected)==12 && observed==12;
        evidence="mimo_impact_raw_trials.csv|mimo_impact_operating_points.csv";
    else
        familyEffects=effects(effects.FamilyID==family,:);
        observed=height(familyEffects);
        threshold=string(cfg.statistics.minimum_finite_pairs)+ ...
            "_paired_effects_evaluated";
        passed=observed>=double(cfg.statistics.minimum_finite_pairs) && ...
            all(isfinite(str2double(familyEffects.AbsoluteEffect)));
        evidence="mimo_impact_pairwise_effects.csv";
    end
    value=localAssign(value,index,struct( ...
        "RunID",runID,"RuleID",rules.RuleID(index), ...
        "FamilyID",family,"Severity",severity, ...
        "Metric",rules.Metric(index),"ObservedValue",observed, ...
        "Threshold",threshold,"Passed",localBool(passed), ...
        "EvidenceCSV",evidence,"Status",localStatus(passed)));
end
end

