classdef PUCCHTransmissionAssignment
    %PUCCHTRANSMISSIONASSIGNMENT Immutable causal PUCCH transmission grant.

    properties (SetAccess=private)
        Data
        Resource
        PowerControlState
        SpatialRelationState
        Digest
    end

    properties (Dependent)
        AssignmentID
        ReportID
        Format
        DueSlot
        ConfigurationEpoch
    end

    methods
        function obj = PUCCHTransmissionAssignment(data,resource,powerState,spatialState)
            required = ["AssignmentID","AssignmentSource","UEID","RNTI", ...
                "ServingCell","PUCCHCell","ComponentCarrier","ActiveULBWP", ...
                "ConfigurationEpoch","ReportID","K1","K1Source","DueSlot", ...
                "ResourceSetID","ResourceID","PRIValue","PRIProvenance", ...
                "PowerControlStateID","SpatialRelationStateID", ...
                "CollisionResolution","ConnectedModeEvidenceEligible"];
            sixgr.phy.pucch.UCIReport.requireFields(data,required);
            if ~isa(resource,"sixgr.phy.pucch.PUCCHResource")
                error("sixgr:phy:pucch:InvalidResourceIndicator", ...
                    "Assignment requires a typed PUCCHResource.");
            end
            if ~isa(powerState,"sixgr.phy.pucch.PUCCHPowerControlState")
                error("sixgr:phy:pucch:InvalidPowerControlState", ...
                    "Assignment requires a typed power-control state.");
            end
            if ~isa(spatialState,"sixgr.phy.pucch.PUCCHSpatialRelationState")
                error("sixgr:phy:pucch:InactiveSpatialRelation", ...
                    "Assignment requires an active spatial relation.");
            end
            if resource.ID ~= double(data.ResourceID)
                error("sixgr:phy:pucch:WrongResource", ...
                    "Assignment and resource IDs differ.");
            end
            obj.Data = data;
            obj.Resource = resource;
            obj.PowerControlState = powerState;
            obj.SpatialRelationState = spatialState;
            digestData = data;
            digestData.ResourceDigest = resource.Digest;
            digestData.PowerDigest = powerState.Digest;
            digestData.SpatialDigest = spatialState.Digest;
            obj.Digest = sixgr.phy.pucch.PUCCHUtil.hash(digestData);
        end

        function value = get.AssignmentID(obj), value = string(obj.Data.AssignmentID); end
        function value = get.ReportID(obj), value = string(obj.Data.ReportID); end
        function value = get.Format(obj), value = obj.Resource.Format; end
        function value = get.DueSlot(obj), value = double(obj.Data.DueSlot); end
        function value = get.ConfigurationEpoch(obj), value = double(obj.Data.ConfigurationEpoch); end
    end

    methods (Static)
        function obj = fromCombinedUCI(report,ueContext,frameState)
            obj = sixgr.phy.pucch.PUCCHTransmissionAssignment.resolve( ...
                report,ueContext,frameState,"combined_uci");
        end

        function obj = fromDynamicHARQ(decodedDCI,pdschEvents,ueContext,frameState)
            if ~isstruct(decodedDCI) || ~isfield(decodedDCI,"EventID") || ...
                    ~isfield(decodedDCI,"PUCCHResourceIndicator") || ...
                    ~isfield(decodedDCI,"K1")
                error("sixgr:phy:pucch:InvalidResourceIndicator", ...
                    "Dynamic HARQ requires decoded DCI event, PRI and K1 provenance.");
            end
            codebook = sixgr.phy.pucch.HARQACKCodebookBuilder.build( ...
                sixgr.phy.pucch.PUCCHUtil.field(decodedDCI, ...
                "CodebookType","TYPE2_DYNAMIC"),pdschEvents, ...
                ueContext.Data.ConfigurationEpoch);
            state = localReportState(ueContext,frameState, ...
                "HARQ_DYNAMIC",string(decodedDCI.EventID),codebook, ...
                struct([]),struct([]));
            report = sixgr.phy.pucch.UCIReport(state);
            frameState.DecodedPRI = decodedDCI.PUCCHResourceIndicator;
            frameState.K1 = decodedDCI.K1;
            frameState.K1Source = "decoded_dci";
            obj = sixgr.phy.pucch.PUCCHTransmissionAssignment.resolve( ...
                report,ueContext,frameState,"dynamic_harq");
        end

        function obj = fromSPSHARQ(spsContext,pdschEvents,ueContext,frameState)
            if ~isstruct(spsContext) || ~isfield(spsContext,"ActivationEventID")
                error("sixgr:phy:pucch:InvalidK1", ...
                    "SPS HARQ requires installed activation context.");
            end
            codebook = sixgr.phy.pucch.HARQACKCodebookBuilder.build( ...
                "TYPE1_SEMISTATIC",pdschEvents,ueContext.Data.ConfigurationEpoch);
            report = sixgr.phy.pucch.UCIReport(localReportState( ...
                ueContext,frameState,"HARQ_SPS", ...
                string(spsContext.ActivationEventID),codebook, ...
                struct([]),struct([])));
            frameState.K1Source = "sps_activation_context";
            obj = sixgr.phy.pucch.PUCCHTransmissionAssignment.resolve( ...
                report,ueContext,frameState,"sps_harq");
        end

        function obj = fromSR(srState,ueContext,frameState)
            if ~isa(srState,"sixgr.phy.pucch.SchedulingRequestState")
                error("sixgr:phy:pucch:MissingSRConfiguration", ...
                    "SR assignment requires SchedulingRequestState.");
            end
            report = sixgr.phy.pucch.UCIReport(localReportState( ...
                ueContext,frameState,"SR_ONLY", ...
                "SR-" + string(srState.Data.SchedulingRequestID), ...
                struct([]),srState,struct([])));
            obj = sixgr.phy.pucch.PUCCHTransmissionAssignment.resolve( ...
                report,ueContext,frameState,"sr");
        end

        function obj = fromCSI(csiState,ueContext,frameState)
            if ~isa(csiState,"sixgr.phy.pucch.CSIReportState")
                error("sixgr:phy:pucch:MissingCSIReportConfiguration", ...
                    "CSI assignment requires CSIReportState.");
            end
            report = sixgr.phy.pucch.UCIReport(localReportState( ...
                ueContext,frameState,"CSI_ONLY", ...
                "CSI-" + string(csiState.Data.ReportID), ...
                struct([]),struct([]),csiState));
            obj = sixgr.phy.pucch.PUCCHTransmissionAssignment.resolve( ...
                report,ueContext,frameState,"csi");
        end

        function obj = forCalibration(request,frameState)
            required = ["AssignmentID","ReportID","RNTI","Resource", ...
                "PowerControlState","SpatialRelationState"];
            sixgr.phy.pucch.UCIReport.requireFields(request,required);
            resource = request.Resource;
            data = struct( ...
                "AssignmentID",string(request.AssignmentID), ...
                "AssignmentSource","calibration", ...
                "UEID",sixgr.phy.pucch.PUCCHUtil.field(request,"UEID",0), ...
                "RNTI",double(request.RNTI),"ServingCell",0,"PUCCHCell",0, ...
                "ComponentCarrier",0,"ActiveULBWP",0, ...
                "ConfigurationEpoch",sixgr.phy.pucch.PUCCHUtil.field( ...
                request,"ConfigurationEpoch",0), ...
                "ReportID",string(request.ReportID), ...
                "K1",0,"K1Source","calibration_explicit", ...
                "DueSlot",sixgr.phy.pucch.PUCCHUtil.field(frameState, ...
                "AbsoluteSlot",0),"ResourceSetID",-1, ...
                "ResourceID",resource.ID,"PRIValue",-1, ...
                "PRIProvenance","calibration_explicit", ...
                "PowerControlStateID",request.PowerControlState.Data.StateID, ...
                "SpatialRelationStateID", ...
                request.SpatialRelationState.Data.SpatialRelationID, ...
                "CollisionResolution","calibration_isolated", ...
                "ConnectedModeEvidenceEligible",false);
            obj = sixgr.phy.pucch.PUCCHTransmissionAssignment( ...
                data,resource,request.PowerControlState, ...
                request.SpatialRelationState);
        end
    end

    methods (Static, Access=private)
        function obj = resolve(report,ueContext,frameState,source)
            if ~isa(report,"sixgr.phy.pucch.UCIReport") || ...
                    ~isa(ueContext,"sixgr.phy.pucch.PUCCHUEContext")
                error("sixgr:phy:pucch:MissingUCIReportContext", ...
                    "Assignment resolution requires typed report and UE state.");
            end
            if report.ConfigurationEpoch ~= ...
                    double(ueContext.Data.ConfigurationEpoch)
                error("sixgr:phy:pucch:StaleConfiguration", ...
                    "Report configuration epoch is stale.");
            end
            if double(report.Data.ULBWP) ~= ...
                    double(ueContext.Data.ActiveULBWP)
                error("sixgr:phy:pucch:StaleBWP", ...
                    "Report UL BWP does not match the active UE UL BWP.");
            end
            if double(report.Data.RNTI) ~= double(ueContext.Data.RNTI)
                error("sixgr:phy:pucch:WrongRNTI", ...
                    "Report RNTI does not match the active UE context.");
            end
            rrc = ueContext.Data.RRCContext;
            set = sixgr.phy.pucch.PUCCHResourceSetResolver.resolve(report,rrc);
            priRow = struct( ...
                "ResourceSetID",set.ID, ...
                "ResourceListSize",numel(set.ResourceIDs), ...
                "PRIFieldWidth",sixgr.phy.pucch.PUCCHUtil.field( ...
                frameState,"PRIFieldWidth",ceil(log2(max(1,numel(set.ResourceIDs))))), ...
                "PRIValue",sixgr.phy.pucch.PUCCHUtil.field(frameState,"DecodedPRI",0), ...
                "FirstCCE",sixgr.phy.pucch.PUCCHUtil.field(frameState,"FirstCCE",NaN), ...
                "NumCCE",sixgr.phy.pucch.PUCCHUtil.field(frameState,"NumCCE",NaN), ...
                "RequiresSet0CCEFormula",set.ID == 0 && numel(set.ResourceIDs)>8);
            pri = sixgr.phy.pucch.PUCCHResourceIndicatorResolver.resolveVector(priRow);
            if ~pri.Valid
                error(pri.ErrorID, ...
                    ["Decoded PUCCH resource indicator is invalid: " + ...
                     "set=%g count=%g width=%g PRI=%g firstCCE=%g numCCE=%g."], ...
                    double(priRow.ResourceSetID), ...
                    double(priRow.ResourceListSize), ...
                    double(priRow.PRIFieldWidth), ...
                    double(priRow.PRIValue), ...
                    double(priRow.FirstCCE), ...
                    double(priRow.NumCCE));
            end
            resource = rrc.resourceByID(set.ResourceIDs(pri.Ordinal));
            k1 = double(sixgr.phy.pucch.PUCCHUtil.field(frameState,"K1",NaN));
            k1Source = string(sixgr.phy.pucch.PUCCHUtil.field( ...
                frameState,"K1Source","decoded_dci"));
            pdschEnd = double(sixgr.phy.pucch.PUCCHUtil.field( ...
                frameState,"PDSCHEndSlot",report.Data.TargetSlot-k1));
            ownership = string(sixgr.phy.pucch.PUCCHUtil.field( ...
                frameState,"SlotSymbolOwnership","UUUUUUUUUUUUUU"));
            timing = sixgr.phy.pucch.PUCCHTimingResolver.resolve( ...
                pdschEnd,k1,k1Source,ownership, ...
                resource.Data.StartSymbol,resource.Data.NumSymbols, ...
                logical(sixgr.phy.pucch.PUCCHUtil.field( ...
                frameState,"FlexibleResolutionProvided",false)));
            serialized = sixgr.phy.pucch.UCIReportSerializer.serialize(report);
            sixgr.phy.pucch.PUCCHFormatValidator.validateResource( ...
                resource.Data,numel(serialized.Sequence1.Bits)+ ...
                numel(serialized.Sequence2.Bits));
            data = struct( ...
                "AssignmentID","PUCCH-" + report.ReportID + "-" + ...
                string(timing.DueSlot), ...
                "AssignmentSource",string(source), ...
                "UEID",ueContext.Data.UEID,"RNTI",ueContext.Data.RNTI, ...
                "ServingCell",ueContext.Data.ServingCell, ...
                "PUCCHCell",ueContext.Data.PUCCHCell, ...
                "ComponentCarrier",ueContext.Data.ComponentCarrier, ...
                "ActiveULBWP",ueContext.Data.ActiveULBWP, ...
                "ConfigurationEpoch",report.ConfigurationEpoch, ...
                "ReportID",report.ReportID,"K1",k1, ...
                "K1Source",k1Source,"DueSlot",timing.DueSlot, ...
                "ResourceSetID",set.ID,"ResourceID",resource.ID, ...
                "PRIValue",priRow.PRIValue, ...
                "PRIProvenance",sixgr.phy.pucch.PUCCHUtil.field( ...
                frameState,"PRIProvenance","decoded_dci"), ...
                "PowerControlStateID", ...
                ueContext.Data.PowerControlState.Data.StateID, ...
                "SpatialRelationStateID", ...
                ueContext.Data.SpatialRelationState.Data.SpatialRelationID, ...
                "CollisionResolution","no_unresolved_collision", ...
                "ConnectedModeEvidenceEligible",true);
            obj = sixgr.phy.pucch.PUCCHTransmissionAssignment( ...
                data,resource,ueContext.Data.PowerControlState, ...
                ueContext.Data.SpatialRelationState);
        end
    end
end

function state = localReportState(ue,frame,source,eventID,harq,sr,csi)
state = struct( ...
    "ReportID",string(source) + "-" + string(eventID), ...
    "RNTI",ue.Data.RNTI,"ServingCell",ue.Data.ServingCell, ...
    "ComponentCarrier",ue.Data.ComponentCarrier, ...
    "ULBWP",ue.Data.ActiveULBWP, ...
    "ConfigurationEpoch",ue.Data.ConfigurationEpoch, ...
    "TargetSlot",sixgr.phy.pucch.PUCCHUtil.field(frame,"TargetSlot",0), ...
    "PriorityIndex",0,"HARQACKReport",harq, ...
    "SchedulingRequestReports",sr,"CSIReports",csi, ...
    "ReportSource",string(source),"TriggeringEventIDs",string(eventID));
end
