classdef PUCCHPowerControlSpec
    %PUCCHPOWERCONTROLSPEC Independent TS 38.213 power expression.
    methods (Static)
        function out = resolve(mu,mrb,p0,pathloss,deltaF,deltaTF,closedLoop,pcmax)
            requested=double(p0)+double(pathloss)+double(deltaF)+ ...
                double(deltaTF)+double(closedLoop)+ ...
                10*log10(max(1,(2^double(mu))*double(mrb)));
            applied=min(double(pcmax),requested);
            out=struct("RequestedPowerdBm",requested, ...
                "AppliedPowerdBm",applied,"Clipped",applied<requested, ...
                "Metadata",sixgr.phy.pucch.oracle.SpecSupport.metadata( ...
                "PUCCHPowerControlSpec"));
        end
    end
end
