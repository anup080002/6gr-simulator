classdef UCISequenceSpec
    %UCISEQUENCESPEC Independent report-owner sequence partition.
    methods (Static)
        function out = resolve(harqBits,srBits,csiPart1Bits,csiPart2Bits)
            widths = double([harqBits srBits csiPart1Bits csiPart2Bits]);
            if any(~isfinite(widths) | widths < 0 | widths ~= fix(widths))
                error("sixgr:phy:pucch:oracle:InvalidWidth", ...
                    "UCI oracle widths must be nonnegative integers.");
            end
            out = struct("Sequence1Length",sum(widths(1:3)), ...
                "Sequence2Length",widths(4), ...
                "SequenceCount",1+double(widths(4)>0), ...
                "OwnerWidths",widths, ...
                "Metadata",sixgr.phy.pucch.oracle.SpecSupport.metadata( ...
                "UCISequenceSpec"));
        end
    end
end
