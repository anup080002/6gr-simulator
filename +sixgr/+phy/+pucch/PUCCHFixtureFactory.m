classdef PUCCHFixtureFactory
    %PUCCHFIXTUREFACTORY Deterministic connected contexts for validation.

    methods (Static)
        function fixture = connected(format,bits,varargin)
            p = inputParser;
            addParameter(p,"RNTI",321,@(x)isnumeric(x)&&isscalar(x));
            addParameter(p,"NSizeGrid",24,@(x)isnumeric(x)&&isscalar(x));
            addParameter(p,"SCS",15,@(x)isnumeric(x)&&isscalar(x));
            addParameter(p,"ResourceID",NaN,@(x)isnumeric(x)&&isscalar(x));
            addParameter(p,"ConfigurationEpoch",1,@(x)isnumeric(x)&&isscalar(x));
            parse(p,varargin{:});
            opt=p.Results;
            format=double(format);
            if nargin<2 || isempty(bits)
                if format<=1, bits=int8(mod((0:format).',2));
                else, bits=int8(mod((0:19).',2)); end
            end
            bits=sixgr.phy.pucch.PUCCHUtil.bits(bits);
            carrier=nrCarrierConfig;
            carrier.NSizeGrid=double(opt.NSizeGrid);
            carrier.SubcarrierSpacing=double(opt.SCS);
            numSymbols=[2 4 2 4 4]; numPRBs=[1 1 4 4 1];
            if ~ismember(format,0:4)
                error("sixgr:phy:pucch:InvalidFormatPayload", ...
                    "Fixture format must be in [0,4].");
            end
            resourceID=double(opt.ResourceID);
            if ~isfinite(resourceID),resourceID=10+format;end
            resourceData=struct("ID",resourceID,"Format",format, ...
                "StartPRB",2+format,"NumPRBs",numPRBs(format+1), ...
                "StartSymbol",14-numSymbols(format+1), ...
                "NumSymbols",numSymbols(format+1), ...
                "IntraSlotHopping",false,"SecondHopStartPRB",NaN, ...
                "InitialCyclicShift",0,"OCCLength",2,"OCCIndex",0, ...
                "AdditionalDMRS",false,"Pi2BPSK",false, ...
                "RNTI",double(opt.RNTI),"NID",10,"HoppingID",10);
            resource=sixgr.phy.pucch.PUCCHResource(resourceData);
            power=sixgr.phy.pucch.PUCCHPowerControlState(struct( ...
                "Mu",log2(double(carrier.SubcarrierSpacing)/15), ...
                "MRB",numPRBs(format+1),"P0dBm",-80, ...
                "PathlossdB",77,"DeltaFdB",0,"DeltaTFdB",0, ...
                "ClosedLoopAdjustmentdB",0,"PCMAXdBm",23, ...
                "PathlossReferenceRSID",1,"TPCCommandSource","decoded_tpc", ...
                "StateID","POWER-"+format));
            spatial=sixgr.phy.pucch.PUCCHSpatialRelationState(struct( ...
                "SpatialRelationID",1,"ActiveSpatialRelationID",1, ...
                "ReferenceSignalType","SSB","ReferenceSignalID",0, ...
                "PathlossReferenceRSID",1,"P0PUCCHID",1, ...
                "ClosedLoopIndex",0,"StateAgeSlots",0,"MaximumAgeSlots",20, ...
                "SelectedBeamID",0,"AppliedBeamID",0));
            if format<=1
                harq=struct("Bits",bits);csi=struct([]);
            else
                harq=struct([]);csi=struct("Part1Bits",bits, ...
                    "Part2Bits",int8([]),"Priority",0,"ReportID",1);
            end
            epoch=double(opt.ConfigurationEpoch);
            report=sixgr.phy.pucch.UCIReport(struct( ...
                "ReportID","REPORT-F"+format,"RNTI",double(opt.RNTI), ...
                "ServingCell",0,"ComponentCarrier",0,"ULBWP",0, ...
                "ConfigurationEpoch",epoch,"TargetSlot",1, ...
                "PriorityIndex",0,"HARQACKReport",harq, ...
                "SchedulingRequestReports",struct([]),"CSIReports",csi, ...
                "ReportSource","decoded_procedure_state", ...
                "TriggeringEventIDs","DCI-F"+format));
            setData=struct("ID",0,"ResourceIDs",resource.ID, ...
                "MaxPayloadBits",1706);
            rrcData=struct("ConfigurationEpoch",epoch, ...
                "ResourceSets",setData,"Resources",resource.Data, ...
                "DLDataToULACK",1,"SRResources",resource.ID, ...
                "CSIResources",resource.ID,"SPSPUCCHANResources",resource.ID);
            rrc=sixgr.phy.pucch.PUCCHRRCContext(rrcData);
            ue=sixgr.phy.pucch.PUCCHUEContext(struct( ...
                "UEID",100+format,"RNTI",double(opt.RNTI), ...
                "ServingCell",0,"PUCCHCell",0,"ComponentCarrier",0, ...
                "ActiveULBWP",0,"ConfigurationEpoch",epoch, ...
                "RRCContext",rrc,"PowerControlState",power, ...
                "SpatialRelationState",spatial));
            frame=struct("K1",1,"K1Source","decoded_dci", ...
                "PDSCHEndSlot",0,"TargetSlot",1,"DecodedPRI",0, ...
                "PRIFieldWidth",0,"PRIProvenance","decoded_dci", ...
                "FirstCCE",0,"NumCCE",24, ...
                "SlotSymbolOwnership","UUUUUUUUUUUUUU", ...
                "FlexibleResolutionProvided",false);
            assignment= ...
                sixgr.phy.pucch.PUCCHTransmissionAssignment.fromCombinedUCI( ...
                report,ue,frame);
            context=sixgr.phy.pucch.UCIReportContext.fromReport(report);
            fixture=struct("Carrier",carrier,"Report",report, ...
                "Assignment",assignment,"Context",context, ...
                "RRCContext",rrc,"UEContext",ue,"FrameState",frame);
        end
    end
end
