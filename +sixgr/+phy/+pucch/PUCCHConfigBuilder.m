classdef PUCCHConfigBuilder
    %PUCCHCONFIGBUILDER Separate causal resource plans from transmit state.
    methods (Static)
        function rrc=receiverConfiguration(cfg,ueData)
            % Installed resource configuration only; no report or UE TX state.
            rrc=localRRC(cfg,ueData);
        end
        function out=planHARQ(cfg,ueData,ack,frame)
            out=localPlan(cfg,ueData,ack,int8([]),int8([]),frame,true);
        end
        function out=planCSI(cfg,ueData,part1,part2,frame)
            out=localPlan(cfg,ueData,int8([]),part1,part2,frame,false);
        end
        function out=planCombined(cfg,ueData,harq,part1,part2,frame)
            out=localPlan(cfg,ueData,harq,part1,part2,frame,false);
        end
        function out=connectedHARQ(cfg,ueData,ack,frame)
            planned=sixgr.phy.pucch.PUCCHConfigBuilder.planHARQ(cfg,ueData,ack,frame);
            out=sixgr.phy.pucch.PUCCHConfigBuilder.materialize(cfg,planned);
        end
        function out=connectedCSI(cfg,ueData,part1,part2,frame)
            planned=sixgr.phy.pucch.PUCCHConfigBuilder.planCSI(cfg,ueData,part1,part2,frame);
            out=sixgr.phy.pucch.PUCCHConfigBuilder.materialize(cfg,planned);
        end
        function out=connectedCombined(cfg,ueData,harq,part1,part2,frame)
            planned=sixgr.phy.pucch.PUCCHConfigBuilder.planCombined(cfg,ueData,harq,part1,part2,frame);
            out=sixgr.phy.pucch.PUCCHConfigBuilder.materialize(cfg,planned);
        end
        function out=materialize(cfg,planned)
            assert(isstruct(planned) && isfield(planned,'Plan') && ...
                isa(planned.Plan,'sixgr.phy.pucch.PUCCHResourcePlan') && ...
                isfield(planned,'Report') && isa(planned.Report,'sixgr.phy.pucch.UCIReport'), ...
                'sixgr:phy:pucch:MissingUCIReportContext','A typed resource plan and its report are required.');
            names={'UEID','RNTI','ServingCell','PUCCHCell','ComponentCarrier','ActiveULBWP','ConfigurationEpoch'};
            ueData=struct();
            for k=1:numel(names), ueData.(names{k})=planned.Plan.Data.(names{k}); end
            [rrc,section]=localRRC(cfg,ueData);
            assert(rrc.Digest==planned.Plan.RRCContextDigest && ...
                planned.Report.Digest==planned.Plan.ReportDigest, ...
                'sixgr:phy:pucch:StaleConfiguration', ...
                'The resource plan must match the current RRC configuration and exact UCI report.');
            % Current causal power evidence is mandatory here, not in planning.
            power=localPower(section,cfg,planned.Plan.Resource);
            spatial=localSpatial(section);
            ueData.RRCContext=rrc;
            ueData.PowerControlState=power;
            ueData.SpatialRelationState=spatial;
            ue=sixgr.phy.pucch.PUCCHUEContext(ueData);
            assignment=sixgr.phy.pucch.PUCCHTransmissionAssignment.fromResourcePlan( ...
                planned.Plan,power,spatial);
            out=struct('RRCContext',rrc,'UEContext',ue,'Report',planned.Report, ...
                'Assignment',assignment,'ReceiverContext', ...
                sixgr.phy.pucch.UCIReportContext.fromReport(planned.Report));
        end
    end
end

function out=localPlan(cfg,ueData,harq,part1,part2,frame,harqOnly)
[rrc,~,epoch]=localRRC(cfg,ueData);
ueData.ConfigurationEpoch=epoch;
harqReport=struct([]);
if isa(harq,'sixgr.phy.pucch.HARQACKCodebookState')
    assert(isscalar(harq) && harq.ConfigurationEpoch==epoch, ...
        'sixgr:phy:pucch:StaleConfiguration','HARQ codebook must match the current PUCCH configuration epoch.');
    harqReport=harq;
    harq=harq.Bits;
else
    harq=sixgr.phy.pucch.PUCCHUtil.bits(harq);
    if ~isempty(harq), harqReport=struct('Bits',harq); end
end
part1=sixgr.phy.pucch.PUCCHUtil.bits(part1);
part2=sixgr.phy.pucch.PUCCHUtil.bits(part2);
due=double(sixgr.phy.pucch.PUCCHUtil.field(frame,'TargetSlot',NaN));
csi=struct([]);
if ~isempty(part1) || ~isempty(part2)
    csi=struct('Part1Bits',part1,'Part2Bits',part2,'Priority',0,'ReportID',1);
end
content="UCI"; source="configured_combined_uci_report_state";
if isempty(harq)
    content="CSI"; source="configured_csi_report_state";
elseif isempty(csi)
    content="HARQ"; source="decoded_harq_procedure_state";
end
event=content+"-TRIGGER-"+string(due);
if harqOnly
    event=string(sixgr.phy.pucch.PUCCHUtil.field(frame,'TriggeringEventID','decoded_harq_event'));
end
report=sixgr.phy.pucch.UCIReport(struct( ...
    'ReportID',content+"-"+string(ueData.UEID)+"-"+string(due), ...
    'RNTI',double(ueData.RNTI),'ServingCell',double(ueData.ServingCell), ...
    'ComponentCarrier',double(ueData.ComponentCarrier),'ULBWP',double(ueData.ActiveULBWP), ...
    'ConfigurationEpoch',epoch,'TargetSlot',due,'PriorityIndex',0, ...
    'HARQACKReport',harqReport,'SchedulingRequestReports',struct([]), ...
    'CSIReports',csi,'ReportSource',source,'TriggeringEventIDs',event));
plan=sixgr.phy.pucch.PUCCHResourcePlan(report,ueData,rrc,frame,"combined_uci");
out=struct('RRCContext',rrc,'Report',report,'Plan',plan, ...
    'ReceiverContext',sixgr.phy.pucch.UCIReportContext.fromReport(report));
end

function [rrc,section,epoch]=localRRC(cfg,ueData)
section=sixgr.util.structGet(cfg,"validation.pucch_resources",struct());
if ~isstruct(section) || ...
        ~logical(sixgr.util.structGet(section,"enabled",false)) || ...
        string(sixgr.util.structGet(section,"profile","")) ~= ...
        "nr_rel18_pucch_strict"
    error("sixgr:phy:pucch:NoSupportingResourceSet", ...
        "Connected PUCCH requires enabled nr_rel18_pucch_strict configuration.");
end
requiredUE=["UEID","RNTI","ServingCell","PUCCHCell", ...
    "ComponentCarrier","ActiveULBWP"];
sixgr.phy.pucch.UCIReport.requireFields(ueData,requiredUE);
epoch=double(sixgr.util.structGet(section, ...
    "configuration_epoch",NaN));
setsIn=sixgr.util.structGet(section,"resource_sets",struct([]));
resourcesIn=sixgr.util.structGet(section,"resources",struct([]));
if ~(isfinite(epoch)&&epoch>=0&&epoch==fix(epoch)) || ...
        ~isstruct(setsIn)||isempty(setsIn)|| ...
        ~isstruct(resourcesIn)||isempty(resourcesIn)
    error("sixgr:phy:pucch:StaleConfiguration", ...
        "Strict PUCCH epoch/resource configuration is incomplete.");
end
sets=repmat(struct("ID",0,"ResourceIDs",[],"MaxPayloadBits",0), ...
    numel(setsIn),1);
for i=1:numel(setsIn)
    sets(i).ID=localRequiredNumber(setsIn(i),["id","set_id"]);
    sets(i).ResourceIDs=double(localRequired( ...
        setsIn(i),["resource_ids"]));
    sets(i).MaxPayloadBits=localRequiredNumber( ...
        setsIn(i),["max_payload_bits"]);
end
resources=repmat(localResourcePrototype(),numel(resourcesIn),1);
for i=1:numel(resourcesIn)
    resources(i)=localResource(resourcesIn(i),double(ueData.RNTI));
end
rrc=sixgr.phy.pucch.PUCCHRRCContext(struct( ...
    "ConfigurationEpoch",epoch,"ResourceSets",sets, ...
    "Resources",resources,"DLDataToULACK", ...
    localRequired(section,["dl_data_to_ul_ack"]), ...
    "SRResources",localRequired(section,["sr_resource_ids"]), ...
    "CSIResources",localRequired(section,["csi_resource_ids"]), ...
    "SPSPUCCHANResources",localRequired( ...
    section,["sps_pucch_an_resource_ids"])));
end

function d=localResource(input,rnti)
d=localResourcePrototype();
d.ID=localRequiredNumber(input,["id","resource_id"]);
d.Format=localRequiredNumber(input,["format"]);
d.StartPRB=localRequiredNumber(input,["starting_prb"]);
d.NumPRBs=localRequiredNumber(input,["nrof_prbs","num_prb"]);
d.StartSymbol=localRequiredNumber(input,["starting_symbol","symbol_start"]);
d.NumSymbols=localRequiredNumber(input,["nrof_symbols","num_symbols"]);
d.IntraSlotHopping=logical(localRequired(input, ...
    ["intra_slot_hopping","intra_slot_frequency_hopping"]));
d.SecondHopStartPRB=localOptionalNumber(input, ...
    ["second_hop_start_prb","second_hop_prb"],NaN);
d.InitialCyclicShift=localRequiredNumber(input,["initial_cyclic_shift"]);
d.OCCLength=localRequiredNumber(input,["occ_length"]);
d.OCCIndex=localRequiredNumber(input,["occ_index"]);
d.AdditionalDMRS=logical(localRequired(input,["additional_dmrs"]));
d.Pi2BPSK=logical(localRequired(input,["pi2_bpsk"]));
d.RNTI=rnti;
d.NID=localRequiredNumber(input,["nid"]);
d.HoppingID=localRequiredNumber(input,["hopping_id"]);
end

function d=localResourcePrototype()
d=struct("ID",0,"Format",0,"StartPRB",0,"NumPRBs",1, ...
    "StartSymbol",0,"NumSymbols",1,"IntraSlotHopping",false, ...
    "SecondHopStartPRB",NaN,"InitialCyclicShift",0, ...
    "OCCLength",1,"OCCIndex",0,"AdditionalDMRS",false, ...
    "Pi2BPSK",false,"RNTI",1,"NID",0,"HoppingID",0);
end

function state=localPower(section,cfg,resource)
p=localRequired(section,["power_control"]);
configuredPathlossdB=localRequiredNumber(p,["pathloss_db"]);
requireMeasuredReference=logical(localOptional( ...
    p,["require_measured_reference_rs"],false));
userMeta=sixgr.util.structGet(cfg,"lls6g.userContext",struct());
runtimePathlossdB=double(sixgr.util.structGet( ...
    userMeta,"RuntimeServingPathloss_dB",NaN));
runtimePathlossSource=strtrim(string(sixgr.util.structGet( ...
    userMeta,"RuntimeServingPathlossSource","")));
runtimeReferenceRS=strtrim(string(sixgr.util.structGet( ...
    userMeta,"RuntimeServingPathlossReferenceRS","")));
runtimeMeasurementId=strtrim(string(sixgr.util.structGet( ...
    userMeta,"RuntimeServingPathlossMeasurementId","")));
runtimeMeasurementSlot=double(sixgr.util.structGet( ...
    userMeta,"RuntimeServingPathlossMeasurementSlot",NaN));
runtimeSignalType=upper(strtrim(string(sixgr.util.structGet( ...
    userMeta,"RuntimeServingPathlossReferenceSignalType",""))));
runtimeSignalId=double(sixgr.util.structGet( ...
    userMeta,"RuntimeServingPathlossReferenceSignalId",NaN));
runtimeMeasurementAvailable=isfinite(runtimePathlossdB) && ...
    runtimePathlossdB>=0 && strlength(runtimePathlossSource)>0 && ...
    strlength(runtimeReferenceRS)>0 && strlength(runtimeMeasurementId)>0;
forbiddenSource=["configured_snr","proxy","fallback","synthetic"];
if runtimeMeasurementAvailable && ...
        any(contains(lower(runtimePathlossSource),forbiddenSource))
    error("sixgr:phy:pucch:InvalidPathlossMeasurementSource", ...
        "PUCCH power control rejected runtime pathloss source '%s'.", ...
        runtimePathlossSource);
end

configuredReference=sixgr.phy.refsig.resolveConfiguredPathlossReference(cfg);
if runtimeMeasurementAvailable && logical(configuredReference.Available)
    if strlength(runtimeSignalType)==0 || ~isfinite(runtimeSignalId) || ...
            runtimeSignalType~=upper(string(configuredReference.SignalType)) || ...
            runtimeSignalId~=double(configuredReference.ReferenceSignalId)
        error("sixgr:phy:pucch:PathlossReferenceIdentityMismatch", ...
            ["PUCCH power control requires measured %s resource %g, but " + ...
             "the runtime measurement identifies %s resource %g."], ...
            string(configuredReference.SignalType), ...
            double(configuredReference.ReferenceSignalId), ...
            runtimeSignalType,runtimeSignalId);
    end
end
if requireMeasuredReference && ~runtimeMeasurementAvailable
    error("sixgr:phy:pucch:PathlossReferenceSignalMeasurementMissing", ...
        ["PUCCH power control requires the causal YAML-selected SSB/CSI-RS " + ...
         "measurement; configured pathloss_db is calibration metadata and " + ...
         "cannot replace runtime waveform evidence."]);
end

pathlossdB=configuredPathlossdB;
pathlossSource="configured_static_calibration_pathloss";
pathlossReferenceRS="configured-pathloss-reference-rs-"+string( ...
    localRequiredNumber(p,["pathloss_reference_rs_id"]));
pathlossMeasurementId="";
pathlossMeasurementSlot=NaN;
stateID="PUCCH-POWER-CONFIG";
if runtimeMeasurementAvailable
    pathlossdB=runtimePathlossdB;
    pathlossSource=runtimePathlossSource;
    pathlossReferenceRS=runtimeReferenceRS;
    pathlossMeasurementId=runtimeMeasurementId;
    pathlossMeasurementSlot=runtimeMeasurementSlot;
    stateID="PUCCH-POWER-RUNTIME-"+runtimeMeasurementId;
end
% TS 38.213 7.2.1: the bandwidth term belongs to THIS resource
% assignment and active carrier, not the static power-calibration scalars.
carrierConfig=sixgr.util.structGet(cfg,"phy.carrier",struct());
scs=localRequiredNumber(carrierConfig,["SubcarrierSpacing"]);
mu=log2(scs/15);
if ~isreal(mu) || ~isfinite(mu) || mu<0 || mu~=fix(mu)
    error("sixgr:phy:pucch:InvalidPowerControlState", ...
        "PUCCH power control requires an explicit valid NR carrier numerology.");
end
state=sixgr.phy.pucch.PUCCHPowerControlState(struct( ...
    "Mu",mu, ...
    "MRB",double(resource.Data.NumPRBs), ...
    "ConfiguredMu",localRequiredNumber(p,["mu"]), ...
    "ConfiguredMRB",localRequiredNumber(p,["m_rb"]), ...
    "BandwidthSource","selected_pucch_resource_and_active_carrier_scs", ...
    "P0dBm",localRequiredNumber(p,["p0_dbm"]), ...
    "PathlossdB",pathlossdB, ...
    "ConfiguredPathlossdB",configuredPathlossdB, ...
    "PathlossSource",pathlossSource, ...
    "PathlossReferenceRS",pathlossReferenceRS, ...
    "PathlossMeasurementId",pathlossMeasurementId, ...
    "PathlossMeasurementSlot",pathlossMeasurementSlot, ...
    "RuntimeMeasuredPathlossUsed",runtimeMeasurementAvailable, ...
    "DeltaFdB",localRequiredNumber(p,["delta_f_db"]), ...
    "DeltaTFdB",localRequiredNumber(p,["delta_tf_db"]), ...
    "ClosedLoopAdjustmentdB",localRequiredNumber( ...
    p,["closed_loop_adjustment_db"]), ...
    "PCMAXdBm",localRequiredNumber(p,["pcmax_dbm"]), ...
    "PathlossReferenceRSID",localRequiredNumber( ...
    p,["pathloss_reference_rs_id"]), ...
    "TPCCommandSource",string(localRequired(p,["tpc_command_source"])), ...
    "StateID",stateID));
end

function state=localSpatial(section)
items=localRequired(section,["spatial_relations"]);
if ~isstruct(items)||isempty(items)
    error("sixgr:phy:pucch:InactiveSpatialRelation", ...
        "At least one configured PUCCH spatial relation is required.");
end
ids=zeros(1,numel(items));
active=zeros(1,numel(items));
for k=1:numel(items)
    ids(k)=localRequiredNumber(items(k),["id"]);
    active(k)=localRequiredNumber(items(k),["active_id"]);
end
if any(ids<0 | ids~=fix(ids)) || any(active<0 | active~=fix(active)) || ...
        numel(unique(ids))~=numel(ids) || numel(unique(active))~=1
    error("sixgr:phy:pucch:AmbiguousSpatialRelation", ...
        "Spatial relations require unique integer IDs and one consistent active_id.");
end
selected=find(ids==active(1));
if numel(selected)~=1
    error("sixgr:phy:pucch:InactiveSpatialRelation", ...
        "The active PUCCH spatial relation is absent from the configured catalog.");
end
p=items(selected);
state=sixgr.phy.pucch.PUCCHSpatialRelationState(struct( ...
    "SpatialRelationID",localRequiredNumber(p,["id"]), ...
    "ActiveSpatialRelationID",localRequiredNumber(p,["active_id"]), ...
    "ReferenceSignalType",string(localRequired( ...
    p,["reference_signal_type"])), ...
    "ReferenceSignalID",localRequiredNumber(p,["reference_signal_id"]), ...
    "PathlossReferenceRSID",localRequiredNumber( ...
    p,["pathloss_reference_rs_id"]), ...
    "P0PUCCHID",localRequiredNumber(p,["p0_pucch_id"]), ...
    "ClosedLoopIndex",localRequiredNumber(p,["closed_loop_index"]), ...
    "StateAgeSlots",localRequiredNumber(p,["state_age_slots"]), ...
    "MaximumAgeSlots",localRequiredNumber(p,["maximum_age_slots"]), ...
    "SelectedBeamID",localRequiredNumber(p,["selected_beam_id"]), ...
    "AppliedBeamID",localRequiredNumber(p,["applied_beam_id"])));
end

function value=localRequired(input,names)
value=[];
for name=string(names)
    if isstruct(input)&&isfield(input,char(name))
        value=input.(char(name));
        if ~isempty(value),return;end
    end
end
error("sixgr:phy:pucch:StaleConfiguration", ...
    "Strict PUCCH configuration is missing %s.",join(string(names)," or "));
end

function value=localOptional(input,names,defaultValue)
value=defaultValue;
for name=string(names)
    if isstruct(input)&&isfield(input,char(name))&&~isempty(input.(char(name)))
        value=input.(char(name));
        return;
    end
end
end

function value=localRequiredNumber(input,names)
value=double(localRequired(input,names));
if ~(isscalar(value)&&isfinite(value))
    error("sixgr:phy:pucch:StaleConfiguration", ...
        "Strict PUCCH field %s must be a finite scalar.",join(string(names),"/"));
end
end

function value=localOptionalNumber(input,names,fallback)
value=fallback;
for name=string(names)
    if isfield(input,char(name)) && ~isempty(input.(char(name)))
        candidate=double(input.(char(name)));
        if isscalar(candidate)&&isfinite(candidate),value=candidate;end
        return;
    end
end
end
