classdef PUCCHPowerControlState
    %PUCCHPOWERCONTROLSTATE Immutable causal PUCCH power-control ledger.

    properties (SetAccess=private)
        Data
        Digest
    end

    methods
        function obj = PUCCHPowerControlState(data)
            required = ["Mu","MRB","P0dBm","PathlossdB","DeltaFdB", ...
                "DeltaTFdB","ClosedLoopAdjustmentdB","PCMAXdBm", ...
                "PathlossReferenceRSID","TPCCommandSource","StateID"];
            sixgr.phy.pucch.UCIReport.requireFields(data,required);
            numericFields = ["Mu","MRB","P0dBm","PathlossdB", ...
                "DeltaFdB","DeltaTFdB","ClosedLoopAdjustmentdB", ...
                "PCMAXdBm","PathlossReferenceRSID"];
            values = zeros(size(numericFields));
            for index = 1:numel(numericFields)
                values(index) = double(data.(numericFields(index)));
            end
            mode=string(sixgr.phy.pucch.PUCCHUtil.field(data,'OperatingPointAuthority','absolute_power_control'));
            if mode=="configured_occupied_re_esn0"
                % A normalized state carries resource identity, not an
                % invented P0/pathloss/device-power result. Its absolute
                % fields must be explicitly unavailable, never zero-filled.
                if ~isreal(values) || any(~isfinite(values([1 2 9]))) || values(1)<0 || ...
                        values(1)~=fix(values(1)) || values(2)<1 || values(2)~=fix(values(2)) || ...
                        values(9)<0 || values(9)~=fix(values(9)) || ...
                        any(~isnan(values(3:8))) || ...
                        ~isequal(sixgr.phy.pucch.PUCCHUtil.field(data,'ReferenceEnergyPerOccupiedRE',NaN),1) || ...
                        ~isequal(sixgr.phy.pucch.PUCCHUtil.field(data,'RuntimeMeasuredPathlossUsed',true),false) || ...
                        strlength(string(sixgr.phy.pucch.PUCCHUtil.field(data,'BandwidthSource','')))==0 || ...
                        strlength(string(data.StateID))==0 || strlength(string(data.TPCCommandSource))==0
                    error('sixgr:phy:pucch:InvalidPowerControlState', ...
                        'Normalized PUCCH requires unit-RE authority and no absolute power/pathloss values.');
                end
                obj.Data=data; obj.Digest=sixgr.phy.pucch.PUCCHUtil.hash(data);
                return;
            elseif mode~="absolute_power_control"
                error('sixgr:phy:pucch:InvalidPowerControlState','Unknown PUCCH operating-point authority.');
            end
            if any(~isfinite(values)) || values(1) < 0 || ...
                    values(1) ~= fix(values(1)) || values(2) < 1 || ...
                    values(2) ~= fix(values(2)) || ...
                    values(4) < 0 || strlength(string(data.StateID)) == 0 || ...
                    strlength(string(data.TPCCommandSource)) == 0
                error("sixgr:phy:pucch:InvalidPowerControlState", ...
                    "PUCCH power-control state is incomplete or nonphysical.");
            end
            obj.Data = data;
            obj.Digest = sixgr.phy.pucch.PUCCHUtil.hash(data);
        end
    end
end
