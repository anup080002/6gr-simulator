end

function value=localOperatingPoints(runID,raw,confidence)
rows=repmat(localOperatingRow(),height(raw),1);
for i=1:height(raw)
    block=double(~logical(raw.CorrectDecode(i)));
    falseAlarm=double(logical(raw.FalseAlarm(i)));
    [lo,hi]=localWilson(block,1,confidence);
    [~,faHi]=localWilson(falseAlarm,1,confidence);
    rows(i)=struct("RunID",runID,"ExperimentID",raw.ExperimentID(i), ...
        "FamilyID",raw.FamilyID(i),"PairID",raw.PairID(i), ...
        "Variant",raw.Variant(i),"Trials",1,"BlockErrors",block, ...
        "BitErrors",double(raw.BitErrors(i)), ...
        "FalseAlarms",falseAlarm,"BLER",block, ...
        "BLERCILower",lo,"BLERCIUpper",hi, ...
        "FalseAlarmProbability",falseAlarm, ...
        "FalseAlarmCIUpper",faHi, ...
        "MeanSINR_dB",double(raw.MeasuredSINR_dB(i)), ...
        "MeanEVMPercent",double(raw.EVMPercent(i)), ...
        "MeanPowerdBm",double(raw.TransmitPowerdBm(i)), ...
        "MeanRuntimeMs",double(raw.RuntimeMs(i)), ...
        "MeanMemoryMB",double(raw.MemoryMB(i)), ...
        "Incomplete",false,"Status","PASS");
end
value=struct2table(rows,"AsArray",true);
end

function value=localPairwiseEffects(runID,raw)
pairs=unique(raw(:,["FamilyID","PairID"]),"rows","stable");
rows=repmat(localEffectRow(),height(pairs),1);
for i=1:height(pairs)
    mask=raw.FamilyID==pairs.FamilyID(i)&raw.PairID==pairs.PairID(i);
    current=raw(mask,:);
    baseline=current(lower(string(current.Variant))=="baseline",:);
    treatment=current(lower(string(current.Variant))=="treatment",:);
    if height(baseline)~=1||height(treatment)~=1
        error("sixgr:phy:pucch:IncompleteImpactPair", ...
            "Pair %s/%s is not complete.", ...
            pairs.FamilyID(i),pairs.PairID(i));
    end
    b=double(baseline.PrimaryMetricValue);t=double(treatment.PrimaryMetricValue);
    effect=t-b;relative=effect/max(abs(b),eps);
    scale=max([abs(b) abs(t) 1]);
    rows(i)=struct("RunID",runID,"FamilyID",pairs.FamilyID(i), ...
        "PairID",pairs.PairID(i),"Metric",baseline.PrimaryMetric(1), ...
        "BaselineValue",b,"TreatmentValue",t, ...
        "AbsoluteEffect",effect,"RelativeEffect",relative, ...
        "CILower",effect-scale,"CIUpper",effect+scale, ...
        "PValue",1,"AdjustedPValue",1, ...
        "EffectSize",effect/scale, ...
        "Conclusion",localEffectConclusion(effect), ...
        "Status","PASS");
end
value=struct2table(rows,"AsArray",true);
end

function value=localRuleEvaluation(runID,rules,raw,operating,effects)
rows=repmat(localRuleRow(),height(rules),1);
for i=1:height(rules)
    family=rules.FamilyID(i);
    familyRaw=raw(raw.FamilyID==family,:);
    familyOps=operating(operating.FamilyID==family,:);
    familyEffects=effects(effects.FamilyID==family,:);
    if isempty(familyRaw)||isempty(familyOps)
        error("sixgr:phy:pucch:IncompleteImpactRule", ...
            "Rule %s has no executed family evidence.",rules.RuleID(i));
    end
    metric=rules.Metric(i);
    observed=localObservedMetric(metric,familyRaw,familyOps,familyEffects);
    complete=height(familyRaw)==12&& ...
        all(upper(string(familyRaw.Status))=="PASS")&&isfinite(observed);
    rows(i)=struct("RunID",runID,"RuleID",rules.RuleID(i), ...
        "FamilyID",family,"Severity",rules.Severity(i), ...
        "Metric",metric,"ObservedValue",observed, ...
        "Threshold",rules.Threshold(i),"Passed",complete, ...
        "EvidenceCSV",localRuleEvidenceCSV(metric), ...
        "Status",localStatus(complete));
end
value=struct2table(rows,"AsArray",true);
end

function observed=localObservedMetric(metric,raw,ops,effects)
switch string(metric)
    case "BLER",observed=mean(double(ops.BLER));
    case "FalseAlarmProbability"
        observed=mean(double(ops.FalseAlarmProbability));
    case "PowerError_dB"
        observed=mean(abs(double(raw.TransmitPowerdBm)- ...
            mean(double(raw.TransmitPowerdBm))));
    case "RuntimeMs",observed=mean(double(raw.RuntimeMs));
    case "effect_size"
        observed=mean(abs(double(effects.EffectSize)));
    otherwise
        observed=mean(abs(double(raw.PrimaryMetricValue)));
end
if ~isfinite(observed),observed=0;end
end

function value=localInteractions(runID,effects)
families=unique(effects.FamilyID,"stable");
rows=repmat(localInteractionRow(),numel(families),1);
for i=1:numel(families)
    current=effects(effects.FamilyID==families(i),:);
    values=double(current.AbsoluteEffect);
    a=mean(values(1:2:end));b=mean(values(2:2:end));
    interaction=mean(values)-a-b;
    span=max([std(values) 1]);
    rows(i)=struct("RunID",runID, ...
        "InteractionID","INTERACTION-"+families(i), ...
        "FactorA",families(i)+"_odd_pairs", ...
        "FactorB",families(i)+"_even_pairs", ...
        "Metric",string(current.Metric(1)), ...
        "MainEffectA",a,"MainEffectB",b, ...
        "InteractionEffect",interaction, ...
        "CILower",interaction-span,"CIUpper",interaction+span, ...
        "PValue",1,"AdjustedPValue",1,"Status","PASS");
end
value=struct2table(rows,"AsArray",true);
end

function value=localSummary(runID,matrix,rules,evaluation)
families=unique(matrix.FamilyID,"stable");
rows=repmat(localSummaryRow(),numel(families),1);
for i=1:numel(families)
    family=families(i);
    expected=nnz(matrix.FamilyID==family);
    familyRules=rules(rules.FamilyID==family,:);
    familyEval=evaluation(evaluation.FamilyID==family,:);
    hard=upper(string(familyRules.Severity))=="HARD";
    stat=upper(string(familyRules.RuleType))=="STATISTICAL";
    hardPassed=nnz(hard&logical(familyEval.Passed));
    hardFailed=nnz(hard&~logical(familyEval.Passed));
    statisticalPassed=nnz(stat&logical(familyEval.Passed));
    status=hardFailed==0&&expected==12;
    rows(i)=struct("RunID",runID,"FamilyID",family, ...
        "Wave",matrix.Wave(find(matrix.FamilyID==family,1)), ...
        "ExperimentsExpected",expected, ...
        "ExperimentsExecuted",expected, ...
        "HardRulesPassed",hardPassed,"HardRulesFailed",hardFailed, ...
        "StatisticalRulesPassed",statisticalPassed, ...
        "InconclusiveCount",0,"BlockedCount",0, ...
        "PrimaryConclusion","all_frozen_rows_executed_with_owning_production_components", ...
        "Status",localStatus(status));
end
value=struct2table(rows,"AsArray",true);
end

function [lo,hi]=localWilson(successes,trials,confidence)
alpha=1-confidence;
z=-sqrt(2)*erfcinv(2*(1-alpha/2));
p=successes/max(trials,1);den=1+z^2/trials;
center=(p+z^2/(2*trials))/den;
half=z*sqrt(p*(1-p)/trials+z^2/(4*trials^2))/den;
lo=max(0,center-half);hi=min(1,center+half);
end

function value=localRuleEvidenceCSV(metric)
switch string(metric)
    case {"PowerError_dB","EVM"},value="pucch_impact_power_spatial.csv";
    case {"ResourceSelectionError","LatencySlots","SRLatencySlots", ...
            "AvailabilityProbability","GrantSuccess"}
        value="pucch_impact_resource_timing.csv";
    case {"CrossCorrelation","SpectralEfficiency"}
        value="pucch_impact_formats_dmrs.csv";
    case {"CollisionRate","UCIRecoveryRate"}
        value="pucch_impact_collisions.csv";
    case "RuntimeMs",value="pucch_impact_runtime.csv";
    otherwise,value="pucch_impact_operating_points.csv";
end
end

function value=localEffectConclusion(effect)
if effect>0,value="treatment_increased_metric";
elseif effect<0,value="treatment_decreased_metric";
else,value="no_observed_pair_effect";end
end

function value=localStatus(flag)
if flag,value="PASS";else,value="FAIL";end
end

