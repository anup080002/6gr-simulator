function summary = runPUCCHImpactAnalysis(varargin)
%RUNPUCCHIMPACTANALYSIS Execute the complete frozen Phase-05 impact matrix.

p=inputParser;
p.FunctionName="sixgr.phy.pucch.runPUCCHImpactAnalysis";
addParameter(p,"ExperimentMatrix","",@(x)ischar(x)||isstring(x));
addParameter(p,"OutputDir","",@(x)ischar(x)||isstring(x));
addParameter(p,"SeedList",[11 23 47 89],@isnumeric);
addParameter(p,"ConfidenceLevel",.95,@(x)isnumeric(x)&&isscalar(x));
addParameter(p,"Strict",true,@(x)islogical(x)&&isscalar(x));
parse(p,varargin{:});
opt=p.Results;
if ~opt.Strict
    error("sixgr:phy:pucch:StrictProfileRequired", ...
        "PUCCH impact evidence requires Strict=true.");
end
matrixPath=string(opt.ExperimentMatrix);
outputDir=string(opt.OutputDir);
if exist(matrixPath,"file")~=2
    error("sixgr:phy:pucch:MissingVectorPack", ...
        "ExperimentMatrix is missing: %s.",matrixPath);
end
if strlength(outputDir)==0
    error("sixgr:phy:pucch:MissingEvidenceOutput", ...
        "OutputDir is mandatory.");
end
if ~isfolder(outputDir),mkdir(outputDir);end
vectorRoot=string(fileparts(matrixPath));
rulePath=fullfile(vectorRoot,"pucch_impact_acceptance_rules.csv");
csvContractPath=fullfile(vectorRoot, ...
    "desired_pucch_impact_csv_contract.csv");
imageContractPath=fullfile(vectorRoot, ...
    "desired_pucch_impact_image_contract.csv");
for required=[rulePath csvContractPath imageContractPath]
    if exist(required,"file")~=2
        error("sixgr:phy:pucch:MissingVectorPack", ...
            "Impact contract is missing: %s.",required);
    end
end
matrix=readtable(matrixPath,"TextType","string", ...
    "VariableNamingRule","preserve");
rules=readtable(rulePath,"TextType","string", ...
    "VariableNamingRule","preserve");
csvContract=readtable(csvContractPath,"TextType","string", ...
    "VariableNamingRule","preserve");
imageContract=readtable(imageContractPath,"TextType","string", ...
    "VariableNamingRule","preserve");
if height(matrix)~=600 || numel(unique(matrix.ExperimentID))~=600
    error("sixgr:phy:pucch:ImpactMatrixInvalid", ...
        "The frozen impact matrix must contain 600 unique experiment rows.");
end
if height(rules)~=75 || numel(unique(rules.RuleID))~=75
    error("sixgr:phy:pucch:ImpactRulesInvalid", ...
        "The frozen acceptance catalog must contain 75 unique rules.");
end
seedList=double(opt.SeedList(:).');
if isempty(seedList)||any(~isfinite(seedList))
    error("sixgr:phy:pucch:ImpactSeedInvalid", ...
        "SeedList must contain finite deterministic seeds.");
end
runID="PUCCH_IMPACT_R18";

rawRows=repmat(localRawRow(),height(matrix),1);
uciRows=repmat(localUCIRow(),height(matrix),1);
timingRows=repmat(localTimingRow(),height(matrix),1);
formatRows=repmat(localFormatRow(),height(matrix),1);
hoppingRows=repmat(localHoppingRow(),height(matrix),1);
powerRows=repmat(localPowerRow(),height(matrix),1);
collisionRows=repmat(localCollisionRow(),height(matrix),1);
receiverRows=repmat(localReceiverRow(),height(matrix),1);
runtimeRows=repmat(localRuntimeRow(),height(matrix),1);

checkpointPath=fullfile(outputDir, ...
    ".pucch_impact_execution_checkpoint.mat");
cacheKey=localExecutionCacheKey(matrixPath,seedList);
cacheUsed=false;
if exist(checkpointPath,"file")==2
    cached=load(checkpointPath);
    names=["rawRows","uciRows","timingRows","formatRows", ...
        "hoppingRows","powerRows","collisionRows", ...
        "receiverRows","runtimeRows"];
    if all(isfield(cached,cellstr(names)))
        exactKey=isfield(cached,"CacheKey")&& ...
            string(cached.CacheKey)==cacheKey;
        verifiedRows=localCacheRowsMatch( ...
            cached.rawRows,matrix,checkpointPath,seedList);
        if exactKey||verifiedRows
            rawRows=cached.rawRows;uciRows=cached.uciRows;
            timingRows=cached.timingRows;formatRows=cached.formatRows;
            hoppingRows=cached.hoppingRows;powerRows=cached.powerRows;
            collisionRows=cached.collisionRows;
            receiverRows=cached.receiverRows;
            runtimeRows=cached.runtimeRows;
            cacheUsed=true;
        end
    end
end
if ~cacheUsed
    for index=1:height(matrix)
        row=matrix(index,:);
        seedGroup=sscanf(char(row.SeedGroup),"%*2c%d");
        if isempty(seedGroup),seedGroup=1;end
        seed=seedList(mod(seedGroup-1,numel(seedList))+1);
        pairIndex=sscanf(char(row.PairID),"%*3c-P%d");
        if isempty(pairIndex),pairIndex=1;end
        try
            evidence=sixgr.phy.pucch.executePUCCHImpactExperiment(row,seed);
        catch ME
            wrapped=MException("sixgr:phy:pucch:ImpactExperimentFailed", ...
                "Experiment %s failed in %s: %s", ...
                row.ExperimentID,string(ME.identifier),string(ME.message));
            wrapped=addCause(wrapped,ME);
            throw(wrapped);
        end
        rawRows(index)=localPopulateRaw(runID,row,seed,pairIndex,evidence);
        uciRows(index)=localPopulate(runID,row,evidence.UCI,localUCIRow());
        timingRows(index)=localPopulate( ...
            runID,row,evidence.ResourceTiming,localTimingRow());
        formatRows(index)=localPopulate( ...
            runID,row,evidence.FormatsDMRS,localFormatRow());
        hoppingRows(index)=localPopulate( ...
            runID,row,evidence.HoppingRepetition,localHoppingRow());
        powerRows(index)=localPopulate( ...
            runID,row,evidence.PowerSpatial,localPowerRow());
        collisionRows(index)=localPopulate( ...
            runID,row,evidence.Collisions,localCollisionRow());
        receiverRows(index)=localPopulate( ...
            runID,row,evidence.Receiver,localReceiverRow());
        runtimeRows(index)=localPopulate( ...
            runID,row,evidence.Runtime,localRuntimeRow());
    end
    CacheKey=cacheKey; %#ok<NASGU>
    save(checkpointPath,"CacheKey","rawRows","uciRows","timingRows", ...
        "formatRows","hoppingRows","powerRows","collisionRows", ...
        "receiverRows","runtimeRows","-v7.3");
end

raw=struct2table(rawRows,"AsArray",true);
operating=localOperatingPoints(runID,raw,opt.ConfidenceLevel);
effects=localPairwiseEffects(runID,raw);
ruleEvaluation=localRuleEvaluation(runID,rules,raw,operating,effects);
interactions=localInteractions(runID,effects);
familySummary=localSummary(runID,matrix,rules,ruleEvaluation);

tables=struct();
tables.pucch_impact_raw_trials=raw;
tables.pucch_impact_operating_points=operating;
tables.pucch_impact_pairwise_effects=effects;
tables.pucch_impact_rule_evaluation=ruleEvaluation;
tables.pucch_impact_uci=struct2table(uciRows,"AsArray",true);
tables.pucch_impact_resource_timing= ...
    struct2table(timingRows,"AsArray",true);
tables.pucch_impact_formats_dmrs= ...
    struct2table(formatRows,"AsArray",true);
tables.pucch_impact_hopping_repetition= ...
    struct2table(hoppingRows,"AsArray",true);
tables.pucch_impact_power_spatial= ...
    struct2table(powerRows,"AsArray",true);
tables.pucch_impact_collisions= ...
    struct2table(collisionRows,"AsArray",true);
tables.pucch_impact_receiver= ...
    struct2table(receiverRows,"AsArray",true);
tables.pucch_impact_runtime= ...
    struct2table(runtimeRows,"AsArray",true);
tables.pucch_impact_interactions=interactions;
tables.pucch_impact_summary=familySummary;

tableNames=string(fieldnames(tables));
rowCounts=struct();csvHashes=struct();
for index=1:numel(tableNames)
    name=tableNames(index);
    fileName=name+".csv";
    sixgr.phy.pucch.PUCCHArtifactExporter.writeTable( ...
        outputDir,fileName,tables.(name));
    rowCounts.(name)=height(tables.(name));
    csvHashes.(name)= ...
        sixgr.phy.pucch.PUCCHArtifactExporter.fileSHA256( ...
        fullfile(outputDir,fileName));
end

auditRows=repmat(localAuditRow(),height(imageContract),1);
for index=1:height(imageContract)
    audit=sixgr.phy.pucch.PUCCHArtifactExporter.writeSemanticFigure( ...
        outputDir,table2struct(imageContract(index,:)));
    audit.RunID=runID;
    auditRows(index)=orderfields(audit,auditRows(index));
end
imageAudit=struct2table(auditRows,"AsArray",true);
imageAudit=movevars(imageAudit,"RunID","Before",1);
sixgr.phy.pucch.PUCCHArtifactExporter.writeTable( ...
    outputDir,"pucch_impact_image_semantic_audit.csv",imageAudit);
rowCounts.pucch_impact_image_semantic_audit=height(imageAudit);
csvHashes.pucch_impact_image_semantic_audit= ...
    sixgr.phy.pucch.PUCCHArtifactExporter.fileSHA256(fullfile( ...
    outputDir,"pucch_impact_image_semantic_audit.csv"));

manifest=sixgr.phy.pucch.buildPUCCHImpactManifest( ...
    runID,matrixPath,seedList,opt.ConfidenceLevel);
sixgr.phy.pucch.PUCCHArtifactExporter.writeTable( ...
    outputDir,"pucch_impact_run_manifest.csv",manifest);
rowCounts.pucch_impact_run_manifest=height(manifest);
csvHashes.pucch_impact_run_manifest= ...
    sixgr.phy.pucch.PUCCHArtifactExporter.fileSHA256(fullfile( ...
    outputDir,"pucch_impact_run_manifest.csv"));

expectedCSV=string(csvContract.FileName);
expectedPNG=string(imageContract.ImageFile);
csvPresent=arrayfun(@(x)exist(fullfile(outputDir,x),"file")==2, ...
    expectedCSV);
pngPresent=arrayfun(@(x)exist(fullfile(outputDir,x),"file")==2, ...
    expectedPNG);
hardMask=upper(string(ruleEvaluation.Severity))=="HARD";
passed=all(csvPresent)&&all(pngPresent)&&height(raw)==600&& ...
    height(operating)==600&&height(effects)==300&& ...
    height(ruleEvaluation)==75&& ...
    all(logical(ruleEvaluation.Passed(hardMask)))&& ...
    all(upper(string(raw.Status))=="PASS")&& ...
    all(upper(string(familySummary.Status))=="PASS");
summary=struct("Passed",passed,"Strict",true,"RunID",runID, ...
    "OutputDir",outputDir,"ExperimentCount",height(raw), ...
    "OperatingPointCount",height(operating), ...
    "PairwiseEffectCount",height(effects), ...
    "RuleCount",height(ruleEvaluation), ...
    "CSVCount",sum(csvPresent),"PNGCount",sum(pngPresent), ...
    "RowCounts",rowCounts,"CSVHashes",csvHashes, ...
    "ExecutionBackend","production_component_and_waveform_truth", ...
    "ApproximationMode","none","Status",localStatus(passed));
if passed&&exist(checkpointPath,"file")==2
    delete(checkpointPath);
end
end

function value=localExecutionCacheKey(matrixPath,seedList)
files=[string(matrixPath),string(which( ...
    "sixgr.phy.pucch.executePUCCHImpactExperiment"))];
payload=struct("Files",files,"Hashes",arrayfun(@(x) ...
    sixgr.phy.pucch.PUCCHArtifactExporter.fileSHA256(x),files), ...
    "SeedList",double(seedList(:).'));
value=sixgr.phy.pucch.PUCCHUtil.hash(payload);
end

function matches=localCacheRowsMatch(rows,matrix,checkpointPath,seedList)
matches=isstruct(rows)&&numel(rows)==height(matrix);
if ~matches,return;end
try
    cached=struct2table(rows,"AsArray",true);
    executorInfo=dir(which( ...
        "sixgr.phy.pucch.executePUCCHImpactExperiment"));
    checkpointInfo=dir(checkpointPath);
    sourcePredatesCache=~isempty(executorInfo)&&~isempty(checkpointInfo)&& ...
        executorInfo.datenum<=checkpointInfo.datenum;
    exactRows=isequal(string(cached.ExperimentID), ...
        string(matrix.ExperimentID))&& ...
        isequal(string(cached.FamilyID),string(matrix.FamilyID))&& ...
        isequal(string(cached.PairID),string(matrix.PairID))&& ...
        isequal(string(cached.Variant),string(matrix.Variant))&& ...
        isequal(string(cached.FactorName),string(matrix.FactorName))&& ...
        isequal(string(cached.FactorValue),string(matrix.FactorValue))&& ...
        isequal(string(cached.BaselineFactorValue), ...
        string(matrix.BaselineFactorValue))&& ...
        isequal(string(cached.PayloadID),string(matrix.PayloadID))&& ...
        isequal(string(cached.Channel),string(matrix.Channel))&& ...
        isequal(string(cached.SNR_dB),string(matrix.SNR_dB));
    allowedSeeds=ismember(double(cached.Seed),double(seedList(:)));
    truthLabels=all(string(cached.ExecutionBackend)== ...
        "production_component_and_waveform_truth")&& ...
        all(string(cached.ApproximationMode)=="none")&& ...
        all(string(cached.Status)=="PASS");
    matches=sourcePredatesCache&&exactRows&&all(allowedSeeds)&&truthLabels;
catch
    matches=false;
end
end

