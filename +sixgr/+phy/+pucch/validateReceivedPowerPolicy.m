function p=validateReceivedPowerPolicy(p)
% Explicit configuration policy; this creates no received/TX evidence.
id='sixgr:phy:pucch:ReceivedPowerPolicy';
assert(isstruct(p)&&isscalar(p),id,'Require one configured power policy.');
p.closed_loop_mode=string(sixgr.util.structGet(p,'closed_loop_mode','configured'));
p.delta_tf_mode=string(sixgr.util.structGet(p,'delta_tf_mode','configured'));
assert(isscalar(p.closed_loop_mode)&&any(p.closed_loop_mode==["configured","received_dci"]) && ...
    isscalar(p.delta_tf_mode)&&any(p.delta_tf_mode==["configured","ts_38_213_payload_resource"]),id, ...
    'Unsupported closed-loop or payload-resource power policy.');
if p.closed_loop_mode=="configured", return; end
assert(string(sixgr.util.structGet(p,'received_dci_installation_policy',''))== ...
    "configured_dedicated_p0_at_first_connected_control_preparation",id, ...
    'Declare the configured-P0 activation boundary separately from received identity.');
policy=string(sixgr.util.structGet(p,'received_dci_autonomous_policy',''));
assert(isscalar(policy)&&any(policy==["response_only","received_common_k2","configured_common_k2"]),id, ...
    'Declare original received-common or explicit configured-common autonomous timing.');
if policy=="configured_common_k2"
    values=sixgr.util.structGet(p,'received_dci_common_k2_slots',[]);
    assert(string(sixgr.util.structGet(p,'received_dci_common_k2_source',''))== ...
        "configured_PUSCH_ConfigCommon_policy" && isa(values,'double') && isvector(values) && ...
        ~isempty(values)&&all(isfinite(values)&values>=0&values<=32&values==fix(values)),id, ...
        'Configured common K2 must be explicit; do not infer it from connected TDRA.');
end
end
