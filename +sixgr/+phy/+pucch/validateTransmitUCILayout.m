function context = validateTransmitUCILayout(report,serialized)
%VALIDATETRANSMITUCILAYOUT Fail before PHY execution on a malformed TX UCI.
% This validates only the transmitter's own typed report and serialization.
% It deliberately does not compare against a receiver hypothesis: a valid
% TX/RX layout mismatch is physical evidence in missing-DCI tests.

id='sixgr:phy:pucch:TransmitUCILayoutMismatch';
assert(isa(report,'sixgr.phy.pucch.UCIReport') && isscalar(report),id, ...
    'PUCCH transmission requires one typed UCIReport.');
assert(isstruct(serialized) && isscalar(serialized) && ...
    all(isfield(serialized,{'Sequence1','Sequence2','Layout'})) && ...
    istable(serialized.Layout),id, ...
    'PUCCH serialization must retain both sequences and its typed layout.');
required={'SequenceIndex','BitOwner','BitValue'};
assert(all(ismember(required,serialized.Layout.Properties.VariableNames)),id, ...
    'PUCCH serialization layout is missing sequence, owner or bit-value evidence.');

context=sixgr.phy.pucch.UCIReportContext.fromReport(report);
sequence1=sixgr.phy.pucch.PUCCHUtil.bits(serialized.Sequence1.Bits);
sequence2=sixgr.phy.pucch.PUCCHUtil.bits(serialized.Sequence2.Bits);
owners=string(serialized.Layout.BitOwner(:));
indices=double(serialized.Layout.SequenceIndex(:));
values=sixgr.phy.pucch.PUCCHUtil.bits(serialized.Layout.BitValue);
wire=[sequence1;sequence2];

assert(numel(sequence1)==context.Sequence1Length && ...
    numel(sequence2)==context.Sequence2Length && height(serialized.Layout)==numel(wire),id, ...
    'Serialized sequence lengths do not match the transmitter typed layout.');
assert(isequal(values,wire) && ...
    nnz(indices==1)==numel(sequence1) && nnz(indices==2)==numel(sequence2) && ...
    all(ismember(indices,[1 2])),id, ...
    'Serialized wire bits and layout rows disagree.');
assert(nnz(owners=="HARQ_ACK")==context.HARQACKBits && ...
    nnz(owners=="SR")==context.SRBits && ...
    nnz(owners=="CSI_PART1")==context.CSIPart1Bits && ...
    nnz(owners=="CSI_PART2")==context.CSIPart2Bits && ...
    nnz(owners=="PADDING")==context.Sequence2Length-context.CSIPart2Bits,id, ...
    'Serialized field ownership does not match HARQ/SR/CSI typed lengths.');
end
