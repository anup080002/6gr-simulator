function accounting=pdschPlanResourceSets(plan)
% Exact carrier-plane identities from the immutable zero-based TX plan.
% This is an index convention adapter, not a TBS or overhead approximation.
accounting=struct('PRBCount',numel(plan.PRBSet), ...
    'SymbolAllocation',plan.SymbolAllocation, ...
    'IndicesIndexBase',"one_based_carrier_plane", ...
    'Source',"immutable_pdsch_resource_plan");
dmrs=unique([plan.DMRSIndicesPerPort{:}]);
ptrs=unique([plan.PTRSIndicesPerPort{:}]);
accounting.Indices=struct('DataBase',double(plan.DataIndices(:))+1, ...
    'DMRSBase',double(dmrs(:))+1,'PTRSBase',double(ptrs(:))+1, ...
    'ReservedBase',double(plan.ReservedUnionIndices(:))+1);
accounting.ResourceSetSummary=sixgr.phy.resource.summarizeResourceSets(accounting);
end
