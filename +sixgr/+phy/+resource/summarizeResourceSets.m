function out=summarizeResourceSets(acct)
% Carrier-plane unions, NOT a sum over antenna ports or codewords.
% "Unoccupied" is scoped to this channel's data/DMRS/PTRS, not other signals.
out=struct('ResourceSetAccountingVersion',"ResourceSets/v2", ...
    'GrossAllocationRE',NaN,'MappedDataBaseRE',NaN, ...
    'PilotOccupiedBaseRE',NaN,'ExplicitReservedBaseRE',NaN, ...
    'UnoccupiedByThisChannelRE',NaN,'NonDataBaseRE',NaN, ...
    'PilotOverGrossFraction',NaN,'NonDataOverGrossFraction',NaN, ...
    'PilotOverDataPlusPilotFraction',NaN, ...
    'UnoccupiedByThisChannelOverGrossFraction',NaN, ...
    'ResourceSetAccountingStatus',"unavailable_exact_allocation_sets", ...
    'ResourceSetAccountingDefinition', ...
    "unique carrier-plane RE; gross=12*allocated_PRBs*allocated_symbols; " + ...
    "pilots=union(DMRS,PTRS); data excludes pilots; " + ...
    "unoccupied_by_this_channel=gross-union(data,pilots), not physical idle RE");
if nargin==0 || ~isstruct(acct), return; end
allocation=sixgr.util.structGet(acct,'SymbolAllocation',[]);
nprb=sixgr.util.structGet(acct,'PRBCount',NaN);
sets=sixgr.util.structGet(acct,'Indices',struct());
if numel(allocation)~=2 || ~all(isfinite(allocation)) || ...
        any(allocation~=fix(allocation)) || allocation(1)<0 || allocation(2)<1 || ...
        ~isscalar(nprb) || ~isfinite(nprb) || nprb<1 || nprb~=fix(nprb) || ...
        ~all(isfield(sets,{'DataBase','DMRSBase','PTRSBase','ReservedBase'}))
    return;
end
for name=["DataBase","DMRSBase","PTRSBase","ReservedBase"]
    value=sets.(name);
    assert(isnumeric(value) && all(isfinite(value(:))) && ...
        all(value(:)>0 & value(:)==fix(value(:))), ...
        'sixgr:phy:resource:InvalidResourceSet','Invalid exact %s RE set.',name);
end
pilots=union(sets.DMRSBase(:),sets.PTRSBase(:));
% Transform-precoded PUSCH's map can include PT-RS puncture locations.
data=setdiff(sets.DataBase(:),pilots);
gross=12*double(nprb)*double(allocation(2));
occupied=union(data,pilots);
allMapped=union(occupied,sets.ReservedBase(:));
assert(numel(allMapped)<=gross,'sixgr:phy:resource:GrossAllocationOverflow', ...
    'Unique mapped and reserved RE exceed the declared gross allocation.');
out.GrossAllocationRE=gross;
out.MappedDataBaseRE=double(numel(data));
out.PilotOccupiedBaseRE=double(numel(pilots));
out.ExplicitReservedBaseRE=double(numel(unique(sets.ReservedBase(:))));
out.UnoccupiedByThisChannelRE=gross-numel(occupied);
out.NonDataBaseRE=gross-numel(data);
out.PilotOverGrossFraction=numel(pilots)/gross;
out.NonDataOverGrossFraction=out.NonDataBaseRE/gross;
if ~isempty(occupied)
    out.PilotOverDataPlusPilotFraction=numel(pilots)/numel(occupied);
end
out.UnoccupiedByThisChannelOverGrossFraction=out.UnoccupiedByThisChannelRE/gross;
out.ResourceSetAccountingStatus="available_exact_channel_resource_sets";
end
