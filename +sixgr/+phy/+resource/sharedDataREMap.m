function map = sharedDataREMap(carrier, channel)
%SHAREDDATAREMAP Exact CP-OFDM shared-channel resource population.
% Coordinates follow native coded-symbol order, relative to the carrier.
% PUSCH includes any multiplexed UCI, not just UL-SCH. This is an allocation
% plan, not evidence that a waveform was transmitted or received.
% nrPUSCHIndices columns are ports for codebook PUSCH; they are NOT rank.
% DFT-s-OFDM needs a post-despreading predictor and is deliberately excluded.
arguments
    carrier (1,1) nrCarrierConfig
    channel (1,1)
end
assert(isa(channel,'nrPDSCHConfig') || isa(channel,'nrPUSCHConfig'), ...
    'sixgr:phy:resource:SharedDataChannel', ...
    'Require the resolved native PDSCH or PUSCH configuration.');
rankValue=double(channel.NumLayers);
if isa(channel,'nrPDSCHConfig')
    name="PDSCH";
    [indices,info]=nrPDSCHIndices(carrier,channel, ...
        'IndexBase','1based','IndexOrientation','carrier');
    columns=rankValue;
    population="pdsch_data_re_excluding_reference_and_reserved_re";
else
    name="PUSCH";
    assert(~channel.TransformPrecoding, ...
        'sixgr:phy:resource:SharedDataTransformPrecoding', ...
        'A per-RE CP-OFDM SINR population cannot represent DFT-s-OFDM.');
    [indices,info]=nrPUSCHIndices(carrier,channel, ...
        'IndexBase','1based','IndexOrientation','carrier');
    columns=rankValue;
    if strcmpi(channel.TransmissionScheme,'codebook')
        columns=double(channel.NumAntennaPorts);
    end
    population="pusch_data_and_uci_re_excluding_reference_re";
end
nSC=12*double(carrier.NSizeGrid);
nSymbols=double(carrier.SymbolsPerSlot);
plane=nSC*nSymbols;
indices=double(indices);
assert(~isempty(indices) && size(indices,2)==columns && ...
    all(isfinite(indices),'all') && all(indices==fix(indices),'all') && ...
    all(indices>=1 & indices<=plane*columns,'all'), ...
    'sixgr:phy:resource:SharedDataDimensions', ...
    'Native shared-channel indices do not match the configured grid/ports.');
physical=mod(indices-1,plane)+1;
base=physical(:,1);
assert(numel(unique(base))==numel(base) && ...
    isequal(physical,repmat(base,1,columns)), ...
    'sixgr:phy:resource:SharedDataOrder', ...
    'Require the same ordered physical RE population on every indexed plane.');
assert(isscalar(info.Gd) && double(info.Gd)==numel(base), ...
    'sixgr:phy:resource:SharedDataCapacity', ...
    'Native symbol capacity and ordered RE count disagree.');
coordinates=[mod(base-1,nSC),floor((base-1)/nSC)];
map=struct('Schema',"sixgr.shared_data_re_map/v1", ...
    'Channel',name,'Waveform',"CP-OFDM", ...
    'Coordinates0Based',coordinates, ...
    'PhysicalIndices1Based',base, ...
    'NativeIndices1Based',indices, ...
    'LayerIndices1Based',base+plane*(0:rankValue-1), ...
    'NumLayers',rankValue,'NativeIndexPlaneCount',columns, ...
    'PhysicalRECount',numel(base),'LayerRECount',numel(base)*rankValue, ...
    'CodedBitsPerCodeword',double(info.G(:).'), ...
    'ResourcePopulation',population, ...
    'Source',"native_nr_shared_channel_allocation_not_waveform_evidence", ...
    'WaveformBacked',false);
end
