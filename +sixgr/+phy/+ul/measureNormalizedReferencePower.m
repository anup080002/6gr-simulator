function evidence=measureNormalizedReferencePower(grid,indices,symbols)
% Diagnostic only: normalized UL grid energy is not UE CSI-RSRP/RSSI/RSRQ.
% Indices are NR Toolbox one-based linear resource indices, including when
% arranged as one column per transmit port. Never interpret Nx2 as subscripts.
validateattributes(grid,{'single','double'},{'nonempty','finite'});
assert(ndims(grid)<=3 && mod(size(grid,1),12)==0, ...
    'sixgr:phy:ul:InvalidReferencePowerGrid','Require a K-by-L-by-R received grid with complete PRBs.');
validateattributes(indices,{'numeric'},{'nonempty','real','finite','integer','positive'});
assert(numel(indices)==numel(symbols) && all(isfinite(symbols(:))), ...
    'sixgr:phy:ul:InvalidReferencePowerIndices','Every linear reference index requires its actual finite symbol.');
K=size(grid,1); L=size(grid,2); R=size(grid,3);
plane=K*L;
active=indices(abs(symbols)>0);
assert(~isempty(active),'sixgr:phy:ul:EmptyReferencePowerResources','No active reference resources.');
re=unique(mod(double(active(:))-1,plane)+1);
subcarrier=mod(re-1,K)+1; symbol=floor((re-1)/K)+1;
rb=unique(floor((subcarrier-1)/12)); symbol=unique(symbol);
sc=reshape(12*rb(:).'+(1:12).',[],1);
branchReference=nan(1,R); branchRSSI=nan(1,R);
symbolPowers=reshape(sum(abs(double(grid(sc,symbol,:))).^2,1),numel(symbol),R);
for r=1:R
    branchReference(r)=mean(abs(double(grid(re+(r-1)*plane))).^2);
    branchRSSI(r)=mean(symbolPowers(:,r));
end
assert(mean(branchReference)>0 && mean(branchRSSI)>0, ...
    'sixgr:phy:ul:ZeroReferencePower','A branch with no measurable energy cannot become a finite dB value.');
evidence=struct('Scope',"normalized_ul_reference_RE_window_not_3gpp_UE_measurement", ...
    'AmplitudeUnit',"receiver_grid_normalized_not_sqrt_W", ...
    'NumReceiveBranches',R,'PRBIndices0Based',rb(:).', ...
    'FrequencyIndexOrigin',"received_grid_first_subcarrier", ...
    'ReferencePortIndices0Based',unique(floor((double(active(:))-1)/plane)).', ...
    'SymbolIndices0Based',symbol(:).'-1, ...
    'ReferenceREPowerPerBranch',branchReference, ...
    'WindowPowerPerSymbolPerBranch',symbolPowers, ...
    'RSSIPerBranch',branchRSSI,'BranchAggregation',"linear_mean_not_sum", ...
    'ReferencePower_dB',10*log10(mean(branchReference)), ...
    'WindowRSSI_dB',10*log10(mean(branchRSSI)), ...
    'WindowPowerRatio_dB',10*log10(numel(rb)*mean(branchReference)/mean(branchRSSI)));
end
