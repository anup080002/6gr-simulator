function plan=planUCIResources(carrier,pusch,targetCodeRate,tbs,lengths)
%PLANUCIRESOURCES Exact TS 38.212 multiplex locations, not transmitted bits.
% Native NR, one codeword. SR is not a PUSCH payload. Short ACK puncturing
% is retained separately from rate matching; GULSCH is NOT simply G-GACK.
arguments
    carrier (1,1) nrCarrierConfig
    pusch (1,1) nrPUSCHConfig
    targetCodeRate (1,1) double {mustBePositive,mustBeFinite}
    tbs (1,1) double {mustBeInteger,mustBePositive}
    lengths (1,3) double {mustBeInteger,mustBeNonnegative}
end
assert(pusch.NumCodewords==1 && targetCodeRate<1 && sum(lengths)>0, ...
    'sixgr:pusch:UCIResourcePlan','Require a single codeword with nonempty HARQ/CSI lengths and rate below one.');
assert(lengths(3)==0 || lengths(2)>0,'sixgr:pusch:UCIResourcePlan','CSI Part 2 requires Part 1.');
info=nrULSCHInfo(pusch,targetCodeRate,tbs,lengths(1),lengths(2),lengths(3));
assert(info.GULSCH>0,'sixgr:pusch:UCIResourcePlan','UCI allocation leaves no UL-SCH capacity.');
% Zero-valued vectors only query the deterministic index permutation; they
% are never exported as PHY payload, CRC evidence or a receive observation.
[cw,map]=nrULSCHMultiplex(pusch,targetCodeRate,tbs, ...
    zeros(info.GULSCH,1,'int8'),zeros(info.GACK,1,'int8'), ...
    zeros(info.GCSI1,1,'int8'),zeros(info.GCSI2,1,'int8'));
[idx,grid]=nrPUSCHIndices(carrier,pusch,'IndexStyle','subscript','IndexBase','0based');
coords=unique(double(idx(:,1:2)),'rows','stable');
G=double(grid.G); qm=G/(size(coords,1)*pusch.NumLayers);
assert(isscalar(G) && numel(cw)==G && isfinite(qm) && qm==fix(qm), ...
    'sixgr:pusch:UCIResourcePlan','Native grid and multiplex bit capacities differ.');
bits=unique([double(map.ACKIndices(:));double(map.CSI1Indices(:));double(map.CSI2Indices(:))]);
assert(~isempty(bits) && all(bits>=1 & bits<=G),'sixgr:pusch:UCIResourcePlan','Invalid native UCI bit indices.');
% Codeword-to-layer mapping cycles through layers for each RE.
re=unique(floor((bits-1)/(qm*pusch.NumLayers))+1);
uciCoords=coords(re,:);
punctured=intersect(double(map.ULSCHIndices(:)),bits);
plan=struct('Schema',"sixgr.native_pusch_uci_resources/v1", ...
    'Source',"nrULSCHInfo_nrULSCHMultiplex_nrPUSCHIndices", ...
    'LengthsHARQCSI1CSI2',lengths,'TargetCodeRate',targetCodeRate,'TBSBits',tbs, ...
    'Modulation',string(pusch.Modulation),'NumLayers',double(pusch.NumLayers), ...
    'PRBSet',double(pusch.PRBSet(:).'),'SymbolAllocation',double(pusch.SymbolAllocation), ...
    'G',G,'GULSCH',double(info.GULSCH),'GACK',double(info.GACK), ...
    'GCSI1',double(info.GCSI1),'GCSI2',double(info.GCSI2),'GACKReserved',double(info.GACKRvd), ...
    'ACKBitIndices',double(map.ACKIndices(:)),'CSI1BitIndices',double(map.CSI1Indices(:)), ...
    'CSI2BitIndices',double(map.CSI2Indices(:)), ...
    'PuncturedULSCHBitIndices',punctured,'PuncturedULSCHBitCount',numel(punctured), ...
    'AllocatedRECount',size(uciCoords,1),'Coordinates0Based',uciCoords, ...
    'WaveformBacked',false,'DecodeQualified',false);
plan.SHA256=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(plan),'UTF-8'))));
end
