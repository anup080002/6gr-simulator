function [blerRows, receiverRows] = localBLERAndReceiverEvidence( ...
        seedList, confidenceLevel)
run = localExecuteNoNoise(6, 1, 1, "QPSK", 0.30, seedList(1));
snrPoints = [-8 -3 2 8];
blerRows = {};
receiverRows = {};
signalPower = mean(abs(run.Tx.Waveform(:)).^2);
for point = 1:numel(snrPoints)
    errors = 0;
    trials = numel(seedList);
    for trial = 1:trials
        rng(seedList(trial) + 1000 * point, "twister");
        noiseVar = signalPower / 10 ^ (snrPoints(point) / 10);
        noise = sqrt(noiseVar / 2) .* ...
            (randn(size(run.Tx.Waveform)) + ...
            1j * randn(size(run.Tx.Waveform)));
        rx = sixgr.phy.ul.PUSCH_Rx( ...
            run.Tx.Waveform + noise, run.Config, ...
            "Carrier", run.Carrier, ...
            "PUSCH", run.PUSCH, ...
            "PUSCHIndices", run.Tx.PUSCHIndices, ...
            "TransportBlockSize", run.Tx.TransportBlockSize, ...
            "TargetCodeRate", run.TargetCodeRate, ...
            "RV", 0, ...
            "CodingLayout", run.Tx.CodingLayout, ...
            "NoiseVar", noiseVar, ...
            "NoiseVarDomain", "time", ...
            "FastAWGNPath", false, ...
            "SkipTimingEstimate", true, ...
            "CompactOutput", false);
        errors = errors + double(~rx.TBCRCPass);
        receiverRows{end+1} = localReceiverRow( ... %#ok<AGROW>
            run, rx, snrPoints(point), point, trial);
    end
    [lowerBound, upperBound] = localWilson( ...
        errors, trials, confidenceLevel);
    bler = errors / trials;
    stopReason = "ci_and_min_errors_met";
    minErrors = 1;
    if errors == 0
        stopReason = "one_sided_censored_precision_met";
        minErrors = 0;
    end
    blerRows{end+1} = struct( ... %#ok<AGROW>
        "CampaignID", "PUSCH-AWGN-R1-QPSK", ...
        "OperatingPointID", sprintf("SNR_%+g", snrPoints(point)), ...
        "SNRdB", snrPoints(point), ...
        "ChannelModel", "AWGN", ...
        "Rank", 1, ...
        "MCSIndex", 4, ...
        "Modulation", "QPSK", ...
        "TransformPrecoding", false, ...
        "FrequencyHopping", "none", ...
        "Trials", trials, ...
        "TBErrors", errors, ...
        "BLER", bler, ...
        "ConfidenceLevel", confidenceLevel, ...
        "CILower", lowerBound, ...
        "CIUpper", upperBound, ...
        "CIHalfWidth", (upperBound - lowerBound) / 2, ...
        "MinErrorsRequired", minErrors, ...
        "StopReason", stopReason, ...
        "Incomplete", false, ...
        "Status", "PASS");
end
end

