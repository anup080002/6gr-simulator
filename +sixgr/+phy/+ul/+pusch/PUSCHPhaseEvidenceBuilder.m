function value = localParseComplexMatrix(raw)
rowTokens = split(string(raw), ";");
rowTokens(rowTokens == "") = [];
parsed = cell(numel(rowTokens), 1);
width = 0;
for row = 1:numel(rowTokens)
    parsed{row} = localParseComplexVector(rowTokens(row));
    width = max(width, numel(parsed{row}));
end
value = complex(zeros(numel(rowTokens), width));
for row = 1:numel(rowTokens)
    if numel(parsed{row}) ~= width
        error("sixgr:pusch:VectorMatrixNotRectangular", ...
            "Frozen complex vector matrix is not rectangular.");
    end
    value(row, :) = parsed{row}.';
end
end

