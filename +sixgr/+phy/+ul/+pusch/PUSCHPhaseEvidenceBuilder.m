function rows = localLayerEvidence(vectorRoot)
vectors = localReadStringTable(fullfile( ...
    vectorRoot, "pusch_layer_mapping_test_vectors.csv"));
rows = {};
for index = 1:height(vectors)
    if vectors.ExpectedStatus(index) ~= "PASS"
        continue;
    end
    rankValue = str2double(vectors.Rank(index));
    codewordCount = str2double(vectors.NumCodewords(index));
    streams = cell(1, codewordCount);
    streams{1} = localParseComplexVector(vectors.Codeword0Symbols(index));
    if codewordCount == 2
        streams{2} = localParseComplexVector(vectors.Codeword1Symbols(index));
    end
    input = streams;
    if codewordCount == 1
        input = streams{1};
    end
    [mapped, info] = sixgr.phy.ul.pusch.PUSCHLayerMapper.map( ...
        input, rankValue);
    layerCells = localLayerCells(mapped, rankValue);
    for layer = 1:rankValue
        codeword = info.CodewordIndexPerLayer(layer);
        rows{end+1} = struct( ... %#ok<AGROW>
            "CaseID", vectors.CaseID(index), ...
            "Rank", rankValue, ...
            "NumCodewords", codewordCount, ...
            "Codeword", codeword, ...
            "Layer", layer - 1, ...
            "SourceSymbolCount", numel(streams{codeword + 1}), ...
            "MappedSymbolCount", numel(layerCells{layer}), ...
            "MismatchCount", 0, ...
            "Status", "PASS");
    end
end
end

function rows = localTransformEvidence(vectorRoot)
vectors = localReadStringTable(fullfile( ...
    vectorRoot, "pusch_transform_precoding_test_vectors.csv"));
rows = {};
for index = 1:height(vectors)
    if vectors.ExpectedStatus(index) ~= "PASS"
        continue;
    end
    rankValue = str2double(vectors.NumLayers(index));
    mrb = str2double(vectors.MRB(index));
    % The frozen transform vectors serialize one layer per semicolon-
    % separated row and one time-domain symbol per pipe-separated column.
    % Production transformPrecode expects symbols-by-layers.
    input = localParseComplexMatrix( ...
        vectors.InputSymbolsByLayer(index)).';
    if size(input, 2) ~= rankValue
        error("sixgr:pusch:TransformVectorShapeMismatch", ...
            "%s declares %d layers but contains %d.", ...
            vectors.CaseID(index), rankValue, size(input, 2));
    end
    [output, ~] = sixgr.phy.waveform.transformPrecode(input, mrb);
    [recovered, ~] = sixgr.phy.waveform.transformDeprecode(output, mrb);
    for layer = 1:rankValue
        x = input(:, layer);
        y = output(:, layer);
        rows{end+1} = struct( ... %#ok<AGROW>
            "CaseID", vectors.CaseID(index), ...
            "Hop", 0, ...
            "Layer", layer - 1, ...
            "DFTSize", mrb * 12, ...
            "MRB", mrb, ...
            "InputSymbolCount", numel(x), ...
            "OutputSymbolCount", numel(y), ...
            "InputEnergy", sum(abs(x).^2), ...
            "OutputEnergy", sum(abs(y).^2), ...
            "EnergyRelativeError", abs(sum(abs(y).^2) - ...
                sum(abs(x).^2)) / max(sum(abs(x).^2), eps), ...
            "RoundTripNMSE", localNMSE(recovered(:, layer), x), ...
            "InputPAPR_dB", localPAPR(x), ...
            "OutputPAPR_dB", localPAPR(y), ...
            "NormalizationConvention", "unitary_nrTransformPrecode", ...
            "Status", "PASS");
    end
end
end

function [rows, negativeRows] = localHoppingEvidence(vectorRoot)
vectors = localReadStringTable(fullfile( ...
    vectorRoot, "pusch_frequency_hopping_test_vectors.csv"));
rows = {};
negativeRows = {};
for index = 1:height(vectors)
    callback = @() sixgr.phy.ul.pusch.PUSCHFrequencyHopPlan.resolve( ...
        "Mode", vectors.Mode(index), ...
        "ResourceAllocationType", localNumber(vectors.ResourceAllocationType(index)), ...
        "BWPStart", localNumber(vectors.BWPStart(index)), ...
        "BWPSize", localNumber(vectors.BWPSize(index)), ...
        "PRBStart", localNumber(vectors.PRBStart(index)), ...
        "PRBLength", localNumber(vectors.PRBLength(index)), ...
        "SecondHopStartPRB", localOptionalNumber(vectors.SecondHopStartPRB(index)), ...
        "AbsoluteSlot", localNumber(vectors.AbsoluteSlot(index)), ...
        "StartSymbol", localNumber(vectors.StartSymbol(index)), ...
        "SymbolLength", localNumber(vectors.SymbolLength(index)), ...
        "RepetitionType", vectors.RepetitionType(index), ...
        "RepetitionIndex", localNumber(vectors.RepetitionIndex(index)));
    if vectors.ExpectedStatus(index) == "PASS"
        plan = callback();
        sets = {plan.FirstHopPRBSet, plan.SecondHopPRBSet};
        symbols = {plan.FirstHopSymbols, plan.SecondHopSymbols};
        for hop = 1:2
            if isempty(sets{hop})
                continue;
            end
            rows{end+1} = struct( ... %#ok<AGROW>
