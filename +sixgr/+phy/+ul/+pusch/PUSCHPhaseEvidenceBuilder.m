function [lowerBound, upperBound] = localWilson(errors, trials, confidence)
z = -sqrt(2) * erfcinv(2 * (1 - (1 - confidence) / 2));
p = errors / trials;
denominator = 1 + z^2 / trials;
center = (p + z^2 / (2 * trials)) / denominator;
radius = z / denominator * sqrt( ...
    p * (1 - p) / trials + z^2 / (4 * trials^2));
lowerBound = max(0, center - radius);
upperBound = min(1, center + radius);
end

function value = localDecisionEVM(symbols, modulation)
if isempty(symbols) || any(~isfinite(symbols))
    value = 0;
    return;
end
hardBits = nrSymbolDemodulate(symbols, char(modulation), ...
    "DecisionType", "hard");
reference = nrSymbolModulate(hardBits, char(modulation));
count = min(numel(symbols), numel(reference));
value = 100 * sqrt(mean(abs(symbols(1:count) - ...
    reference(1:count)).^2) / ...
    max(mean(abs(reference(1:count)).^2), eps));
end
