function [resourceRows, reRows] = localAppendRE( ...
        resourceRows, reRows, subs, caseId, domain, hop)
for index = 1:size(subs, 1)
    absoluteSubcarrier = double(subs(index, 1));
    symbol = double(subs(index, 2));
    port = double(subs(index, 3));
    prb = floor(absoluteSubcarrier / 12);
    withinPRB = mod(absoluteSubcarrier, 12);
    owner = domain;
    codeword = 0;
    layer = min(port, 0);
    resourceRows{end+1} = struct( ... %#ok<AGROW>
        "CaseID", caseId, ...
        "Slot", 0, ...
        "Hop", hop, ...
        "PRB", prb, ...
        "Symbol", symbol, ...
        "Subcarrier", withinPRB, ...
        "Owner", owner, ...
        "UEID", "UE1", ...
        "Codeword", codeword, ...
        "Layer", layer, ...
        "Port", port, ...
        "SourceResourceId", caseId + "-" + domain, ...
        "CollisionCount", 0, ...
        "Status", "PASS");
    reRows{end+1} = struct( ... %#ok<AGROW>
        "CaseID", caseId, ...
        "Domain", domain, ...
        "Hop", hop, ...
        "Codeword", codeword, ...
        "Layer", layer, ...
        "Port", port, ...
        "PRB", prb, ...
        "Symbol", symbol, ...
        "Subcarrier", withinPRB, ...
        "LinearIndex0Based", absoluteSubcarrier + ...
            symbol * 12 * 12 + port * 12 * 12 * 14, ...
        "Status", "PASS");
end
end

