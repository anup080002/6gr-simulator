function value = localText(raw)
if isempty(raw)
    value = "";
elseif islogical(raw)
    value = join(string(double(raw(:).')), "|");
elseif isnumeric(raw)
    if ~isreal(raw)
        tokens = strings(1, numel(raw));
        values = raw(:).';
        for index = 1:numel(values)
            tokens(index) = compose("%.17g%+.17gj", ...
                real(values(index)), imag(values(index)));
        end
        value = join(tokens, "|");
    else
        value = join(compose("%.17g", double(raw(:).')), "|");
    end
elseif iscell(raw)
    value = join(string(raw), "|");
else
    value = join(string(raw(:).'), "|");
end
value = string(value);
if ismissing(value)
    value = "";
end
end

