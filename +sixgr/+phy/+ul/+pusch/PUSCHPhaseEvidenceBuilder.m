function value = localArrayDigest(array)
if isempty(array)
    value = string(sixgr.util.sha256Hex(uint8([])));
    return;
end
if isnumeric(array) || islogical(array)
    realBytes = typecast(double(real(array(:))), "uint8");
    imagBytes = typecast(double(imag(array(:))), "uint8");
    shapeBytes = typecast(uint64(size(array)), "uint8");
    bytes = [shapeBytes(:); realBytes(:); imagBytes(:)];
else
    bytes = uint8(unicode2native(char(string(array)), "UTF-8"));
end
value = string(sixgr.util.sha256Hex(bytes));
end

function value = localFileSHA256(path)
fid = fopen(path, "rb");
if fid < 0
    error("sixgr:pusch:PhaseArtifactReadFailed", ...
        "Unable to read %s.", path);
end
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid, Inf, "*uint8");
value = string(sixgr.util.sha256Hex(bytes));
clear cleanup
end

function value = localNMSE(actual, expected)
actual = complex(double(actual(:)));
expected = complex(double(expected(:)));
if numel(actual) ~= numel(expected)
    value = Inf;
    return;
end
value = sum(abs(actual - expected).^2) / ...
    max(sum(abs(expected).^2), eps);
end

