classdef PUSCHPhaseEvidenceBuilder
    %PUSCHPHASEEVIDENCEBUILDER Build production-derived Prompt-03 evidence.
    %
    % Frozen expected files are used only as independent comparison
    % inputs.  Primary tables are assembled from executed production
    % objects, waveforms, decoders, estimators, and validators.

    methods (Static)
        function evidence = build(vectorRoot, seedList, confidenceLevel, testSummary)
            vectorRoot = char(string(vectorRoot));
            if ~isfolder(vectorRoot)
                error("sixgr:pusch:PhaseVectorRootMissing", ...
                    "PUSCH vector root does not exist: %s", vectorRoot);
            end
            seedList = double(seedList(:).');
            if isempty(seedList) || any(~isfinite(seedList) | seedList ~= fix(seedList))
                error("sixgr:pusch:PhaseSeedListInvalid", ...
                    "SeedList must contain finite integers.");
            end
            if ~(isscalar(confidenceLevel) && isfinite(confidenceLevel) ...
                    && confidenceLevel > 0 && confidenceLevel < 1)
                error("sixgr:pusch:PhaseConfidenceInvalid", ...
                    "ConfidenceLevel must be strictly between zero and one.");
            end
            if ~istable(testSummary)
                error("sixgr:pusch:PhaseTestSummaryMissing", ...
                    "Observed focused-test summary is required.");
            end

            [assignmentRows, assignmentNegative] = ...
                localAssignmentEvidence(vectorRoot);
            [resourceRows, reRows, dmrsRows, ptrsRows] = ...
                localResourceAndReferenceEvidence();
            [uciRows, uciNegative] = localUCIEvidence();
            [codingRows, baseRun] = localCodingEvidence();
            layerRows = localLayerEvidence(vectorRoot);
            transformRows = localTransformEvidence(vectorRoot);
            [hopRows, hopNegative] = localHoppingEvidence(vectorRoot);
            srsRows = localSRSEvidence(vectorRoot);
            precoderRows = localPrecoderEvidence();
            [powerRows, powerNegative] = localPowerEvidence(vectorRoot);
            harqRows = localHARQEvidence(baseRun);
            [blerRows, receiverRows] = localBLERAndReceiverEvidence( ...
                seedList, confidenceLevel);
            modulationNegative = localModulationNegativeEvidence(vectorRoot);
            layerNegative = localLayerNegativeEvidence(vectorRoot);
            negativeRows = [ ...
                assignmentNegative, uciNegative, hopNegative, ...
                powerNegative, modulationNegative, layerNegative];
            independentRows = localIndependentEvidence(vectorRoot, struct( ...
                "Assignment", {assignmentRows}, ...
                "Resource", {resourceRows}, ...
                "DMRS", {dmrsRows}, ...
                "PTRS", {ptrsRows}, ...
                "UCI", {uciRows}, ...
                "Coding", {codingRows}, ...
                "Layer", {layerRows}, ...
                "Transform", {transformRows}, ...
                "Hopping", {hopRows}, ...
                "SRS", {srsRows}, ...
                "Precoder", {precoderRows}, ...
                "Power", {powerRows}, ...
                "HARQ", {harqRows}, ...
                "Receiver", {receiverRows}));

            evidence = struct();
            evidence.pusch_assignment_resolution = localContractTable( ...
                assignmentRows, "pusch_assignment_resolution.csv", vectorRoot);
            evidence.pusch_resource_ownership = localContractTable( ...
                resourceRows, "pusch_resource_ownership.csv", vectorRoot);
            evidence.pusch_re_mapping = localContractTable( ...
                reRows, "pusch_re_mapping.csv", vectorRoot);
            evidence.pusch_dmrs_matrix = localContractTable( ...
                dmrsRows, "pusch_dmrs_matrix.csv", vectorRoot);
            evidence.pusch_ptrs_matrix = localContractTable( ...
                ptrsRows, "pusch_ptrs_matrix.csv", vectorRoot);
            evidence.pusch_uci_multiplexing = localContractTable( ...
                uciRows, "pusch_uci_multiplexing.csv", vectorRoot);
            evidence.pusch_coding_chain = localContractTable( ...
                codingRows, "pusch_coding_chain.csv", vectorRoot);
            evidence.pusch_independent_vector_results = localContractTable( ...
                independentRows, "pusch_independent_vector_results.csv", vectorRoot);
            evidence.pusch_codeword_layer_map = localContractTable( ...
                layerRows, "pusch_codeword_layer_map.csv", vectorRoot);
            evidence.pusch_transform_precoding = localContractTable( ...
                transformRows, "pusch_transform_precoding.csv", vectorRoot);
            evidence.pusch_frequency_hopping = localContractTable( ...
                hopRows, "pusch_frequency_hopping.csv", vectorRoot);
            evidence.pusch_srs_precoder_selection = localContractTable( ...
                srsRows, "pusch_srs_precoder_selection.csv", vectorRoot);
            evidence.pusch_precoding_application = localContractTable( ...
                precoderRows, "pusch_precoding_application.csv", vectorRoot);
            evidence.pusch_power_control = localContractTable( ...
                powerRows, "pusch_power_control.csv", vectorRoot);
            evidence.pusch_harq_trials = localContractTable( ...
                harqRows, "pusch_harq_trials.csv", vectorRoot);
            evidence.pusch_receiver_metrics = localContractTable( ...
                receiverRows, "pusch_receiver_metrics.csv", vectorRoot);
            evidence.pusch_bler_curve = localContractTable( ...
                blerRows, "pusch_bler_curve.csv", vectorRoot);
            evidence.pusch_negative_tests = localContractTable( ...
                negativeRows, "pusch_negative_tests.csv", vectorRoot);
            evidence.pusch_test_summary = localContractTable( ...
                localTestSummaryRows(testSummary), ...
                "pusch_test_summary.csv", vectorRoot);
        end
    end
end

function [rows, negativeRows] = localAssignmentEvidence(vectorRoot)
vectors = localReadStringTable(fullfile( ...
    vectorRoot, "pusch_scheduling_assignment_test_vectors.csv"));
rows = {};
negativeRows = {};
for index = 1:height(vectors)
    input = table2struct(vectors(index, :));
    created = false;
    actualError = "";
    resolved = struct();
    try
        assignment = sixgr.phy.ul.pusch.PUSCHAssignmentFactory.fromVectorRow(input);
        assignment.validateForExecution();
        resolved = assignment.toStruct();
        created = true;
    catch caught
        actualError = string(caught.identifier);
    end
    expectedPass = vectors.ExpectedStatus(index) == "PASS";
    if created ~= expectedPass
        error("sixgr:pusch:AssignmentVectorOutcomeMismatch", ...
            "%s expected %s but production creation state was %d (%s).", ...
            vectors.CaseID(index), vectors.ExpectedStatus(index), ...
            created, actualError);
    end
    if ~expectedPass && actualError ~= vectors.ExpectedError(index)
        error("sixgr:pusch:AssignmentVectorErrorMismatch", ...
            "%s expected %s but production raised %s.", ...
            vectors.CaseID(index), vectors.ExpectedError(index), actualError);
    end
    row = struct( ...
        "CaseID", vectors.CaseID(index), ...
        "Profile", vectors.Profile(index), ...
        "UEID", vectors.UEID(index), ...
        "ServingCellID", vectors.ServingCellID(index), ...
        "CCID", vectors.CCID(index), ...
        "BWPId", vectors.BWPId(index), ...
        "AbsoluteSlot", vectors.AbsoluteSlot(index), ...
        "ConfigurationEpoch", vectors.ConfigurationEpoch(index), ...
        "AssignmentSource", localStructText(resolved, "Source", vectors.SourceType(index)), ...
        "DecodedDCIId", vectors.DecodedDCIId(index), ...
        "DCIFormat", vectors.DCIFormat(index), ...
        "DCICRCPass", vectors.DCICRCPass(index), ...
        "DCIRNTIMatch", vectors.DCIRNTIMatch(index), ...
        "RNTIType", vectors.RNTIType(index), ...
        "ConfiguredGrantID", vectors.ConfiguredGrantID(index), ...
        "CGType", vectors.CGType(index), ...
        "CGInstalled", vectors.CGInstalled(index), ...
        "CGActivated", vectors.CGActivated(index), ...
        "CGReleased", vectors.CGReleased(index), ...
        "CGOccasionMatch", vectors.CGOccasionMatch(index), ...
        "RARGrantID", vectors.RARGrantID(index), ...
        "K2", vectors.K2(index), ...
        "ULSymbolAvailable", vectors.ULSymbolAvailable(index), ...
        "ResourceAllocationType", vectors.ResourceAllocationType(index), ...
        "FrequencyHopping", vectors.FrequencyHopping(index), ...
        "SecondHopStartPRB", vectors.SecondHopStartPRB(index), ...
        "PRBSet", localStructText(resolved, "PRBSetBWPRelative", vectors.PRBSet(index)), ...
        "SymbolAllocation", localStructText(resolved, "SymbolAllocation", vectors.SymbolAllocation(index)), ...
        "MappingType", localStructText(resolved, "MappingType", vectors.MappingType(index)), ...
        "MCSTable", vectors.MCSTable(index), ...
        "MCSIndex", vectors.MCSIndex(index), ...
        "Modulation", localStructText(resolved, "ModulationPerCodeword", ""), ...
        "TargetCodeRate", localStructText(resolved, "TargetCodeRatePerCodeword", ""), ...
        "TransformPrecoding", vectors.TransformPrecoding(index), ...
        "NumLayers", vectors.NumLayers(index), ...
        "NumCodewords", localStructText(resolved, "NumCodewords", ""), ...
        "TransmissionScheme", vectors.TransmissionScheme(index), ...
        "SRI", vectors.SRI(index), ...
        "TPMI", vectors.TPMI(index), ...
        "NDI", vectors.NDI(index), ...
        "RV", vectors.RV(index), ...
        "HARQProcessID", vectors.HARQProcessID(index), ...
        "SRSDecisionID", localConditionalText(created, "SRS-DEC-" + vectors.CaseID(index)), ...
        "PowerControlStateID", localConditionalText(created, "PWR-" + vectors.CaseID(index)), ...
        "AssignmentCreated", created, ...
        "WaveformAllowed", created, ...
        "ErrorIdentifier", actualError, ...
        "Status", "PASS");
    rows{end+1} = row; %#ok<AGROW>
    if ~created
        negativeRows{end+1} = localNegativeRow( ... %#ok<AGROW>
            vectors.CaseID(index), "scheduling_assignment", ...
            vectors.ExpectedError(index), actualError);
    end
end
end

