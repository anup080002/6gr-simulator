function value = localTable(contract, fileName, nRows)
match = find(string(contract.FileName) == string(fileName), 1);
if isempty(match)
    error("sixgr:pusch:ImpactContractMissing", ...
        "No impact CSV contract exists for %s.", fileName);
end
columns = split(string(contract.RequiredColumns(match)), "|").';
value = array2table(strings(nRows, numel(columns)), ...
    "VariableNames", cellstr(columns));
end

function value = localAssign(value, index, input)
names = string(value.Properties.VariableNames);
for name = names
    field = char(name);
    if isfield(input, field)
        value.(field)(index) = localTextValue(input.(field));
    end
end
end

function value = localTextValue(input)
if islogical(input)
    value = lower(string(input));
elseif isnumeric(input)
    if isempty(input)
        value = "";
    elseif isscalar(input)
        value = string(double(input));
    else
        value = join(compose("%.15g", double(input(:).')), "|");
    end
elseif isdatetime(input)
    value = string(input);
else
    value = string(input);
end
if ismissing(value)
    value = "";
end
end

function value = localReadStrings(path)
if ~isfile(path)
    error("sixgr:pusch:ImpactInputMissing", ...
        "Required PUSCH impact input is missing: %s.", path);
end
options = detectImportOptions(path, FileType="text", Delimiter=",", ...
    VariableNamingRule="preserve");
options = setvartype(options, options.VariableNames, "string");
value = readtable(path, options);
for index = 1:width(value)
    name = value.Properties.VariableNames{index};
    column = string(value.(name));
    column(ismissing(column)) = "";
    value.(name) = column;
end
end

function value = localFileHash(path)
fid = fopen(path, "rb");
if fid < 0
    error("sixgr:pusch:ImpactArtifactReadFailed", ...
        "Unable to read %s.", path);
end
cleanup = onCleanup(@() fclose(fid));
value = string(sixgr.util.sha256Hex(fread(fid, Inf, "*uint8")));
clear cleanup
end

