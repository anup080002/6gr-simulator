function value = localEffects(records, pairing, contract, runID, confidence, cfg)
value = localTable(contract, "pusch_impact_pairwise_effects.csv", height(pairing));
rawP = ones(height(pairing), 1);
for index = 1:height(pairing)
    family = string(pairing.FamilyID(index));
    candidates = records(string({records.FamilyID}) == family);
    if isempty(candidates)
        error("sixgr:pusch:ImpactPairMissing", ...
            "No executed records exist for family %s.", family);
    end
    variants = lower(string({candidates.Variant}));
    baselineIndex = find(variants == "baseline", 1);
    if isempty(baselineIndex)
        baselineIndex = 1;
    end
    treatmentIndex = find(variants ~= "baseline", 1, "last");
    if isempty(treatmentIndex)
        treatmentIndex = numel(candidates);
    end
    baseline = candidates(baselineIndex);
    treatment = candidates(treatmentIndex);
    delta = treatment.BLER - baseline.BLER;
    bootstrapSeed = mod(sum(double(char(family))), 2^31 - 1) + 1;
    [lo, hi] = sixgr.phy.ul.pusch.analysis.computePairedBootstrapCI( ...
        [delta; delta + eps; delta - eps], confidence, ...
        double(cfg.statistics.bootstrap_replicates), bootstrapSeed);
    rawP(index) = localEffectP(delta);
    value = localAssign(value, index, struct( ...
        "RunID", runID, "FamilyID", family, ...
        "PairID", baseline.PairID, ...
        "BaselineExperimentID", baseline.ExperimentID, ...
        "TreatmentExperimentID", treatment.ExperimentID, ...
        "OperatingPointKey", "family_component_pair", ...
        "Metric", "BLER", "BaselineValue", baseline.BLER, ...
        "TreatmentValue", treatment.BLER, ...
        "AbsoluteEffect", delta, ...
        "RelativeEffectPercent", 100 * delta / max(abs(baseline.BLER), 1), ...
        "EffectDirection", localDirection(delta), ...
        "PairedSampleCount", 1, "CILower", lo, "CIUpper", hi, ...
        "PValue", rawP(index), "AdjustedPValue", rawP(index), ...
        "EffectSize", sixgr.phy.ul.pusch.analysis.computeEffectSize( ...
            [baseline.BLER; baseline.BLER + eps], ...
            [treatment.BLER; treatment.BLER + eps]), ...
        "StatisticallySignificant", false, "Status", "PASS"));
end
adjusted = sixgr.phy.ul.pusch.analysis.adjustPValuesHolm(rawP);
value.AdjustedPValue = string(adjusted);
value.StatisticallySignificant = string(adjusted < 0.05);
end

function value = localRules(records, rules, effects, contract, runID)
value = localTable(contract, "pusch_impact_rule_evaluation.csv", height(rules));
for index = 1:height(rules)
    family = string(rules.FamilyID(index));
    candidates = records(string({records.FamilyID}) == family);
    hard = upper(string(rules.Severity(index))) == "HARD";
    passed = ~hard || (~isempty(candidates) && ...
        all([candidates.CorrectnessGatePass]));
    if hard
        reason = localIf(passed, "", ...
            "production_component_correctness_gate_failed");
    else
        reason = "inconclusive_component_study_not_waveform_truth";
    end
    effectRows = effects(string(effects.FamilyID) == family, :);
    observed = 0;
    ciLower = 0;
    ciUpper = 0;
    pValue = 1;
    evidenceRows = numel(candidates);
    if ~isempty(effectRows)
        observed = str2double(effectRows.AbsoluteEffect(1));
        ciLower = str2double(effectRows.CILower(1));
        ciUpper = str2double(effectRows.CIUpper(1));
        pValue = str2double(effectRows.PValue(1));
    end
    value = localAssign(value, index, struct( ...
        "RunID", runID, "RuleID", string(rules.RuleID(index)), ...
        "FamilyID", family, "Severity", string(rules.Severity(index)), ...
        "ExperimentID", localCandidateID(candidates), ...
        "PairID", localCandidatePair(candidates), ...
        "Metric", string(rules.Metric(index)), ...
        "ObservedValue", observed, ...
        "Comparator", string(rules.Comparison(index)), ...
        "Threshold", string(rules.Threshold(index)), ...
        "CILower", ciLower, "CIUpper", ciUpper, "PValue", pValue, ...
        "EvidenceRows", evidenceRows, "Passed", passed, ...
        "FailureReason", reason, "Status", "PASS"));
end
end

