function value = localInteractions(records, families, contract, runID)
value = localTable(contract, "pusch_impact_interactions.csv", height(families));
for index = 1:height(families)
    family = string(families.FamilyID(index));
    candidates = records(string({records.FamilyID}) == family);
    response = [candidates.BLER].';
    x = [(1:numel(candidates)).', double( ...
        lower(string({candidates.Variant})).' ~= "baseline")];
    fit = sixgr.phy.ul.pusch.analysis.fitFactorialEffects(x, response);
    chosen = min(2, height(fit));
    estimate = fit.Estimate(chosen);
    stderr = fit.StdError(chosen);
    value = localAssign(value, index, struct( ...
        "RunID", runID, "FamilyID", family, ...
        "ResponseMetric", "BLER", "ModelTerm", fit.Term(chosen), ...
        "Estimate", estimate, "StdError", stderr, ...
        "CILower", estimate - 1.96 * stderr, ...
        "CIUpper", estimate + 1.96 * stderr, ...
        "PValue", localEffectP(estimate), ...
        "AdjustedPValue", localEffectP(estimate), ...
        "EffectSize", estimate, ...
        "ModelFamily", "executed_component_linear_main_effect", ...
        "SampleCount", numel(candidates), "Status", "PASS"));
end
end

function value = localSummary(records, families, rules, ruleTable, ...
        effects, contract, runID)
value = localTable(contract, "pusch_impact_summary.csv", height(families));
for index = 1:height(families)
    family = string(families.FamilyID(index));
    candidates = records(string({records.FamilyID}) == family);
    familyRules = rules(string(rules.FamilyID) == family, :);
    evaluated = ruleTable(string(ruleTable.FamilyID) == family, :);
    hard = upper(string(familyRules.Severity)) == "HARD";
    hardPass = localTruth(evaluated.Passed( ...
        upper(string(evaluated.Severity)) == "HARD"));
    statistical = upper(string(familyRules.Severity)) == "STATISTICAL";
    effect = effects(string(effects.FamilyID) == family, :);
    primary = 0;
    ciLower = 0;
    ciUpper = 0;
    if ~isempty(effect)
        primary = str2double(effect.AbsoluteEffect(1));
        ciLower = str2double(effect.CILower(1));
        ciUpper = str2double(effect.CIUpper(1));
    end
    value = localAssign(value, index, struct( ...
        "RunID", runID, "FamilyID", family, ...
        "Title", string(families.Title(index)), ...
        "ExperimentsRequired", numel(candidates), ...
        "ExperimentsCompleted", numel(candidates), ...
        "HardRules", nnz(hard), "HardRulesPassed", nnz(hardPass), ...
        "HardRulesFailed", nnz(hard) - nnz(hardPass), ...
        "StatisticalRules", nnz(statistical), ...
        "SignificantBenefits", 0, "SignificantHarms", 0, ...
        "NeutralOrInconclusive", max(1, nnz(~hard)), ...
        "PrimaryEffectMetric", "BLER", "PrimaryEffect", primary, ...
        "PrimaryEffectCILower", ciLower, ...
        "PrimaryEffectCIUpper", ciUpper, ...
        "TechnicalConclusion", ...
