classdef PUSCHImpactEvidenceBuilder
    %PUSCHIMPACTEVIDENCEBUILDER Build contract tables from executed rows.

    methods (Static)
        function [tables, summary, records] = build( ...
                matrixPath, pairingPath, rulesPath, analyticalFloorPath, ...
                vectorRoot, cfg, runID, seedList, confidence)
            matrix = localReadStrings(matrixPath);
            pairing = localReadStrings(pairingPath);
            rules = localReadStrings(rulesPath);
            floor = localReadStrings(analyticalFloorPath); %#ok<NASGU>
            families = localReadStrings(fullfile( ...
                vectorRoot, "pusch_impact_analysis_families.csv"));
            contract = localReadStrings(fullfile( ...
                vectorRoot, "desired_pusch_impact_csv_contract.csv"));
            localValidateInputs(matrix, pairing, rules, families, cfg);

            records = repmat(localEmptyRecord(), height(matrix), 1);
            for index = 1:height(matrix)
                try
                    records(index) = ...
                        sixgr.phy.ul.pusch.analysis. ...
                        PUSCHImpactExperimentExecutor.execute( ...
                            matrix(index, :), cfg, seedList);
                catch cause
                    failure = MException( ...
                        "sixgr:pusch:ImpactExperimentExecutionFailed", ...
                        "Experiment %s failed production-component execution.", ...
                        string(matrix.ExperimentID(index)));
                    failure = addCause(failure, cause);
                    throw(failure);
                end
            end

            raw = localRaw(records, contract, runID);
            operating = localOperating(records, contract, runID, confidence);
            effects = localEffects(records, pairing, contract, runID, ...
                confidence, cfg);
            ruleTable = localRules(records, rules, effects, contract, runID);

            tables = struct();
            tables.pusch_impact_raw_trials = raw;
            tables.pusch_impact_operating_points = operating;
            tables.pusch_impact_pairwise_effects = effects;
            tables.pusch_impact_rule_evaluation = ruleTable;
            tables.pusch_impact_uci = localUCI(records, contract, runID);
            tables.pusch_impact_dmrs_ptrs = ...
                localDMRSPTRS(records, matrix, contract, runID);
            tables.pusch_impact_transform_hopping = ...
                localTransformHopping(records, matrix, contract, runID);
            tables.pusch_impact_srs_precoding = ...
                localSRS(records, matrix, contract, runID);
            tables.pusch_impact_power_control = ...
                localPower(records, matrix, contract, runID);
            tables.pusch_impact_harq_receiver = ...
                localHARQ(records, matrix, contract, runID);
            tables.pusch_impact_grant_cg_ra = ...
                localGrant(records, matrix, contract, runID);
            tables.pusch_impact_runtime = ...
                localRuntime(records, matrix, contract, runID);
            tables.pusch_impact_interactions = ...
                localInteractions(records, families, contract, runID);
            tables.pusch_impact_summary = ...
                localSummary(records, families, rules, ruleTable, ...
                effects, contract, runID);
            tables.pusch_impact_run_manifest = localManifest( ...
                matrixPath, rulesPath, records, contract, runID, ...
                seedList, cfg);

            hard = upper(string(rules.Severity)) == "HARD";
            hardIDs = string(rules.RuleID(hard));
            evaluatedHard = ruleTable(ismember( ...
                string(ruleTable.RuleID), hardIDs), :);
            hardPass = all(localTruth(evaluatedHard.Passed));
            summary = struct( ...
                "ExperimentCount", height(matrix), ...
                "CompletedCount", numel(records), ...
                "PairCount", height(pairing), ...
                "RuleCount", height(rules), ...
                "HardRuleCount", nnz(hard), ...
                "HardRulePassCount", nnz(localTruth(evaluatedHard.Passed)), ...
                "IncompleteCount", 0, ...
                "HardRulesPassed", hardPass, ...
                "ExecutionBackend", string(cfg.evidence.execution_backend), ...
                "ApproximationMode", string(cfg.evidence.approximation_mode), ...
                "TruthQualified", logical(cfg.evidence.truth_qualified));
        end
    end
end

function localValidateInputs(matrix, pairing, rules, families, cfg)
if height(matrix) ~= 705 || numel(unique(string(matrix.ExperimentID))) ~= 705
    error("sixgr:pusch:ImpactMatrixInvalid", ...
        "The frozen impact matrix must contain 705 unique experiments.");
end
if height(pairing) ~= 52 || height(families) ~= 52
    error("sixgr:pusch:ImpactMatrixInvalid", ...
        "The impact pack must contain 52 pairing rows and 52 families.");
end
if height(rules) ~= 70 || numel(unique(string(rules.RuleID))) ~= 70
    error("sixgr:pusch:ImpactRulesInvalid", ...
        "The impact pack must contain 70 unique acceptance rules.");
end
matrixFamilies = unique(string(matrix.FamilyID));
if ~isequal(sort(matrixFamilies), sort(string(families.FamilyID)))
    error("sixgr:pusch:ImpactMatrixInvalid", ...
        "Experiment and family IDs are not closed under the frozen pack.");
end
required = [ ...
    "evidence.execution_backend","evidence.approximation_mode", ...
    "evidence.truth_qualified","monte_carlo.symbols_per_experiment", ...
    "monte_carlo.covariance_samples", ...
    "monte_carlo.minimum_covariance_samples", ...
    "statistics.bootstrap_replicates","images.width_pixels", ...
    "images.height_pixels","images.resolution_dpi"];
for path = required
    if isempty(sixgr.util.structGet(cfg, path, []))
        error("sixgr:pusch:ImpactStudyConfigInvalid", ...
            "StudyConfig requires field %s.", path);
    end
end
if logical(cfg.evidence.truth_qualified)
    error("sixgr:pusch:ImpactTruthRelabelForbidden", ...
        "The component campaign cannot set truth_qualified=true.");
end
end

