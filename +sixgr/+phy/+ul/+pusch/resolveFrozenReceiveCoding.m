function opt=resolveFrozenReceiveCoding(opt,grant)
% gNB receiver parameters come from its own frozen grant, not UE TX state
% or a stale YAML initial RV / nominal TBS recomputed for new resources.
values=struct('RV',double(grant.HARQProcessKey.RV), ...
    'TransportBlockSize',double(grant.CodingLayout.TBSBits), ...
    'TargetCodeRate',double(grant.CodingLayout.TargetCodeRate));
for name=string(fieldnames(values)).'
    value=values.(name);
    assert(isnumeric(value) && isvector(value) && all(isfinite(value)), ...
        'sixgr:phy:ul:PUSCHFrozenReceiveCodingMissing', ...
        'Frozen gNB %s must be finite; receiver defaults are not retransmission authority.',name);
    supplied=opt.(name);
    assert(isempty(supplied) || (numel(supplied)==numel(value) && ...
        all(abs(double(supplied(:))-value(:))<1e-12)), ...
        'sixgr:phy:ul:PUSCHFrozenReceiveCodingMismatch', ...
        'Explicit receiver %s disagrees with the gNB frozen grant.',name);
    opt.(name)=value;
end
end
