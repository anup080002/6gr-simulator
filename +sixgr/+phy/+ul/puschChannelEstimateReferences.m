function reference=puschChannelEstimateReferences(rx)
% Reference coordinates for the effective-layer Hest returned by PUSCH_Rx.
% Native codebook DMRSIndices index antenna ports; Hest indexes layers.
% Derive the same unprecoded references used by the practical estimator
% from the received/configured PUSCH, never from transmitter bits or H truth.
assert(isstruct(rx) && isscalar(rx) && isfield(rx,'Carrier') && ...
    isfield(rx,'PUSCH') && isfield(rx,'ChannelEstimate') && ...
    ~isempty(rx.ChannelEstimate), ...
    'sixgr:phy:ul:MissingPUSCHChannelReferenceContext', ...
    'Require the actual receiver carrier, PUSCH configuration and Hest.');
carrier=rx.Carrier;
pusch=rx.PUSCH;
assert(isa(carrier,'nrCarrierConfig') && isa(pusch,'nrPUSCHConfig'), ...
    'sixgr:phy:ul:InvalidPUSCHChannelReferenceContext', ...
    'Reference coordinates must come from installed receiver configurations.');
amplitude=sixgr.util.structGet(rx,'DMRSAmplitudeScale',NaN);
validateattributes(amplitude,{'numeric'},{'scalar','finite','positive'});
layers=double(pusch.NumLayers);
physicalPorts=double(pusch.NumAntennaPorts);
if strcmpi(string(pusch.TransmissionScheme),'codebook')
    % Value-object copy: preserve the received physical-port configuration.
    pusch.TransmissionScheme='nonCodebook';
end
indices=nrPUSCHDMRSIndices(carrier,pusch,'IndexStyle','index','IndexBase','1based');
symbols=nrPUSCHDMRS(carrier,pusch)*double(amplitude);
source="received_PUSCH_configuration_effective_layer_DMRS";
capturedFields={'ChannelEstimateReferenceIndices','ChannelEstimateReferenceSymbols', ...
    'ChannelEstimateReferenceDomain'};
if any(isfield(rx,capturedFields))
    assert(all(isfield(rx,capturedFields)) && ...
        string(rx.ChannelEstimateReferenceDomain)=="effective_layer_channel" && ...
        isequal(rx.ChannelEstimateReferenceIndices,indices) && ...
        isequal(rx.ChannelEstimateReferenceSymbols,symbols), ...
        'sixgr:phy:ul:PUSCHCapturedReferenceMismatch', ...
        'Captured estimator references must match the received PUSCH layer domain and power scaling.');
    indices=rx.ChannelEstimateReferenceIndices;
    symbols=rx.ChannelEstimateReferenceSymbols;
    source="actual_PUSCH_receiver_channel_estimator_inputs";
end
h=rx.ChannelEstimate;
K=double(carrier.NSizeGrid)*12; L=double(carrier.SymbolsPerSlot);
assert(size(h,1)==K && size(h,2)==L && size(h,4)==layers && ...
    size(symbols,2)==layers && isequal(size(indices),size(symbols)) && ...
    all(double(indices(:))<=K*L*layers), ...
    'sixgr:phy:ul:PUSCHChannelReferenceDomainMismatch', ...
    'Effective Hest and DM-RS references must share the same K/L/RX/layer domain.');
reference=struct('Indices',indices,'Symbols',symbols, ...
    'IndexBase',"1based",'Domain',"effective_layer_channel", ...
    'LogicalPortCount',layers,'PhysicalTransmitPortCount',physicalPorts, ...
    'NumReceiveBranches',size(h,3),'DMRSAmplitudeScale',double(amplitude), ...
    'Source',source, ...
    'TransmitterPayloadUsed',false,'TrueChannelUsed',false);
end
