function [rx, info] = PUCCH_Rx(rxWaveform, cfg, assignment, reportContext, varargin)
%PUCCH_RX Compatibility facade for the canonical oracle-free PUCCH receiver.
%
% The receiver obtains report field widths from UCIReportContext. It never
% receives transmitted report values, comparison data, or a fallback length.

p = inputParser;
p.FunctionName = "sixgr.phy.ul.PUCCH_Rx";
addRequired(p,"rxWaveform",@(x) isnumeric(x)&&~isempty(x));
addRequired(p,"cfg",@(x) isstruct(x)||isobject(x));
addRequired(p,"assignment", ...
    @(x) isa(x,"sixgr.phy.pucch.PUCCHTransmissionAssignment"));
addRequired(p,"reportContext", ...
    @(x) isa(x,"sixgr.phy.pucch.UCIReportContext"));
addParameter(p,"Carrier",[],@(x) isempty(x)||isa(x,"nrCarrierConfig"));
addParameter(p,"NoiseVariance",0, ...
    @(x) isnumeric(x)&&isscalar(x));
addParameter(p,"NoiseVarianceDomain","sample", ...
    @(x) ischar(x)||isstring(x));
addParameter(p,"ChannelProfile","AWGN",@(x) ischar(x)||isstring(x));
addParameter(p,"DetectionThreshold",0.2, ...
    @(x) isnumeric(x)&&isscalar(x)&&x>=0&&x<=1);
parse(p,rxWaveform,cfg,assignment,reportContext,varargin{:});

carrier = p.Results.Carrier;
if isempty(carrier)
    if isa(cfg,"nrCarrierConfig")
        carrier = cfg;
    else
        carrier = sixgr.phy.grid.makeCarrier(cfg);
    end
end
rx = sixgr.phy.pucch.PUCCHReceiver.receive( ...
    rxWaveform,carrier,assignment,reportContext, ...
    "NoiseVariance",p.Results.NoiseVariance, ...
    "NoiseVarianceDomain",p.Results.NoiseVarianceDomain, ...
    "ChannelProfile",p.Results.ChannelProfile, ...
    "DetectionThreshold",p.Results.DetectionThreshold);
info = struct( ...
    "ReceiverUsable",rx.ReceiverUsable, ...
    "DetectionAttempted",rx.DetectionAttempted, ...
    "DTX",rx.DTX, ...
    "DetectionMetric",rx.DetectionMetric, ...
    "AssignmentDigest",rx.AssignmentDigest, ...
    "ReportContextDigest",rx.ReportContextDigest, ...
    "OraclePayloadBitsUsed",false, ...
    "FailureReason",rx.FailureReason, ...
    "ErrorID",rx.ErrorID, ...
    "OFDMInfo",rx.OFDMInfo);
end
