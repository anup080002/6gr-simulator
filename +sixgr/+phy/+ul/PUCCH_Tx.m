function [tx, info] = PUCCH_Tx(cfg, assignment, report, varargin)
%PUCCH_TX Compatibility facade for the canonical typed PUCCH transmitter.
%
% Connected operation requires a PUCCHTransmissionAssignment and UCIReport.
% Synthetic flat-bit calibration is intentionally isolated in
% sixgr.phy.pucch.runCalibrationTrial and is never connected-mode evidence.

p = inputParser;
p.FunctionName = "sixgr.phy.ul.PUCCH_Tx";
addRequired(p,"cfg",@(x) isstruct(x)||isobject(x));
addRequired(p,"assignment", ...
    @(x) isa(x,"sixgr.phy.pucch.PUCCHTransmissionAssignment"));
addRequired(p,"report",@(x) isa(x,"sixgr.phy.pucch.UCIReport"));
addParameter(p,"Carrier",[],@(x) isempty(x)||isa(x,"nrCarrierConfig"));
parse(p,cfg,assignment,report,varargin{:});
if isstruct(cfg)
    configuredPUCCH = logical(sixgr.util.structGet(cfg, "phy.pucch.enable", false));
    sixgr.config.assertRuntimeFeatureUse(cfg, "pucch", configuredPUCCH, ...
        "PUCCH_Tx");
    if ~configuredPUCCH
        error("sixgr:phy:pucch:DisabledByYAML", ...
            "PUCCH Tx cannot execute when PUCCH is disabled by YAML.");
    end
end

carrier = p.Results.Carrier;
if isempty(carrier)
    if isa(cfg,"nrCarrierConfig")
        carrier = cfg;
    else
        carrier = sixgr.phy.grid.makeCarrier(cfg);
    end
end
tx = sixgr.phy.pucch.PUCCHTransmitter.transmit( ...
    carrier,assignment,report);
info = struct( ...
    "Format",assignment.Format, ...
    "AssignmentDigest",tx.AssignmentDigest, ...
    "ReportDigest",tx.ReportDigest, ...
    "SerializationDigest",tx.SerializationDigest, ...
    "CodingPlanDigest",tx.CodingPlanDigest, ...
    "ResourceOwnershipDigest",tx.ResourceOwnershipDigest, ...
    "DMRSSequenceDigest",tx.DMRSSequenceDigest, ...
    "DMRSIndexDigest",tx.DMRSIndexDigest, ...
    "PowerStateDigest",tx.PowerStateDigest, ...
    "SpatialStateDigest",tx.SpatialStateDigest, ...
    "WaveformSHA256",tx.WaveformSHA256, ...
    "OFDMInfo",tx.OFDMInfo, ...
    "ExecutionProfile",tx.ExecutionProfile, ...
    "ConnectedModeEvidenceEligible",tx.ConnectedModeEvidenceEligible);
end
