function alignment=pdcchReceivedClockAlignment(reference,carrier,nominalStart,fs,filterDelay)
% Align a PDCCH observation using a previously received SS/PBCH clock.
% The implementation filter latency is known hardware metadata, not a
% channel timing oracle. Neither DCI samples nor actual path gains are used.
required={'Source','SampleRateHz','AvailableAtSample','DLPhaseOffsetSamples', ...
    'NCellID','ImplementationFilterDelay_samples','SearchGuardSamples'};
assert(isstruct(reference) && isscalar(reference) && all(isfield(reference,required)), ...
    'sixgr:phy:frame:MissingPDCCHReceivedClock','Retain the actual decoded SS/PBCH timing reference.');
validateattributes(nominalStart,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(fs,{'numeric'},{'scalar','real','finite','positive'});
validateattributes(filterDelay,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(reference.AvailableAtSample,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(reference.DLPhaseOffsetSamples,{'numeric'},{'scalar','real','finite','integer'});
validateattributes(reference.SearchGuardSamples,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
assert(string(reference.Source)=="received_SSB_timing_and_decoded_BCH" && ...
    reference.SampleRateHz==fs && reference.NCellID==carrier.NCellID && ...
    reference.ImplementationFilterDelay_samples==filterDelay && ...
    abs(reference.DLPhaseOffsetSamples)<=reference.SearchGuardSamples, ...
    'sixgr:phy:frame:PDCCHReceivedClockMismatch', ...
    'Cell identity, sample clock, receive phase and calibrated filter latency must agree.');
shift=double(reference.DLPhaseOffsetSamples)+double(filterDelay);
receiveStart=nominalStart+shift;
assert(receiveStart>=0 && reference.AvailableAtSample<=min(nominalStart,receiveStart), ...
    'sixgr:phy:frame:FuturePDCCHReceivedClock', ...
    'A control observation cannot use timing learned from its own or a future reception.');
alignment=struct('Source',"received_SSB_clock_aligned_observation", ...
    'SampleRateHz',fs,'NominalStartSample',nominalStart,'ReceiveStartSample',receiveStart, ...
    'AppliedObservationShiftSamples',shift,'AvailableAtSample',reference.AvailableAtSample, ...
    'Reference',reference,'ReceiverPaddingApplied',false,'TruePathDelayUsed',false);
end
