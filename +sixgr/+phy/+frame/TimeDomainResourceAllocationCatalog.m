classdef TimeDomainResourceAllocationCatalog
    %TIMEDOMAINRESOURCEALLOCATIONCATALOG Pinned selected Release-18 TDRA rows.
    %
    % This is deliberately a small production anchor, not a fabricated
    % complete table.  Every supported identifier names one exact row from
    % ETSI TS 138 214 V18.8.0 (3GPP TS 38.214 Release 18).  A configured
    % row outside this selected set must be supplied as an explicit,
    % validated test/configuration grant.

    properties (Constant)
        StandardRelease = "3GPP Release 18"
        SpecificationVersion = "V18.8.0"
        SpecificationURI = ...
            "https://www.etsi.org/deliver/etsi_ts/138200_138299/138214/18.08.00_60/ts_138214v180800p.pdf"
    end

    methods (Static)
        function rows = selectedRows()
            %SELECTEDROWS Return the intentionally supported catalog rows.
            %
            % The PUSCH default-A table defines K2 using j.  These two
            % selected UL rows are pinned at mu_PUSCH=0, where Table
            % 6.1.2.1.1-4 defines j=1.
            rows = [ ...
                localRow( ...
                    "PDSCH_DEFAULT_A_NCP_R1_DMRS2", "PDSCH", ...
                    "5.1.2.1.1-2", "default_A_normal_CP", 1, ...
                    2, NaN, "A", 0, NaN, "0", NaN, 2, 12); ...
                localRow( ...
                    "PDSCH_DEFAULT_A_NCP_R6_DMRS2", "PDSCH", ...
                    "5.1.2.1.1-2", "default_A_normal_CP", 6, ...
                    2, NaN, "B", 0, NaN, "0", NaN, 9, 4); ...
                localRow( ...
                    "PDSCH_DEFAULT_B_NCP_R6_DMRS2", "PDSCH", ...
                    "5.1.2.1.1-4", "default_B", 6, ...
                    2, NaN, "B", 1, NaN, "1", NaN, 2, 2); ...
                localRow( ...
                    "PDSCH_DEFAULT_B_NCP_R14_DMRS2", "PDSCH", ...
                    "5.1.2.1.1-4", "default_B", 14, ...
                    2, NaN, "A", 0, NaN, "0", NaN, 2, 12); ...
                localRow( ...
                    "PUSCH_DEFAULT_A_NCP_R1_MU0", "PUSCH", ...
                    "6.1.2.1.1-2", "default_A_normal_CP", 1, ...
                    NaN, 0, "A", NaN, 1, "j", 1, 0, 14); ...
                localRow( ...
                    "PUSCH_DEFAULT_A_NCP_R4_MU0", "PUSCH", ...
                    "6.1.2.1.1-2", "default_A_normal_CP", 4, ...
                    NaN, 0, "B", NaN, 1, "j", 1, 2, 10) ...
                ];
        end

        function row = resolve(id, varargin)
            %RESOLVE Resolve one pinned row without inferring another row.
            p = inputParser;
            p.FunctionName = ...
                "sixgr.phy.frame.TimeDomainResourceAllocationCatalog.resolve";
            addRequired(p, "id", @(x) ischar(x) || ...
                (isstring(x) && isscalar(x)));
            addParameter(p, "SymbolsPerSlot", 14, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x));
            addParameter(p, "DMRSTypeAPosition", NaN, ...
                @(x) isnumeric(x) && isscalar(x));
            addParameter(p, "Mu", NaN, ...
                @(x) isnumeric(x) && isscalar(x));
            parse(p, id, varargin{:});

            id = upper(strtrim(string(p.Results.id)));
            rows = sixgr.phy.frame. ...
                TimeDomainResourceAllocationCatalog.selectedRows();
            match = find(upper(string({rows.ID})) == id);
            if numel(match) ~= 1
                error("sixgr:phy:frame:UnknownTDRACatalogID", ...
                    "TDRA catalog ID '%s' is not in the selected " + ...
                    "TS 38.214 V18.8.0 production anchor.", id);
            end
            row = rows(match);

            symbolsPerSlot = double(p.Results.SymbolsPerSlot);
            if symbolsPerSlot ~= row.SymbolsPerSlot
                error("sixgr:phy:frame:TDRACyclicPrefixMismatch", ...
                    "TDRA %s requires %d symbols per slot; received %g.", ...
                    row.ID, row.SymbolsPerSlot, symbolsPerSlot);
            end
            requestedDMRS = double(p.Results.DMRSTypeAPosition);
            if isfinite(requestedDMRS) && ...
                    isfinite(row.DMRSTypeAPosition) && ...
                    requestedDMRS ~= row.DMRSTypeAPosition
                error("sixgr:phy:frame:TDRADMRSTypeAPositionMismatch", ...
                    "TDRA %s is pinned for dmrs-TypeA-Position=%d; " + ...
                    "received %g.", row.ID, row.DMRSTypeAPosition, ...
                    requestedDMRS);
            end
            requestedMu = double(p.Results.Mu);
            if isfinite(requestedMu) && isfinite(row.Mu) && ...
                    requestedMu ~= row.Mu
                error("sixgr:phy:frame:TDRANumerologyMismatch", ...
                    "TDRA %s is pinned for mu=%d; received %g.", ...
                    row.ID, row.Mu, requestedMu);
            end
        end

        function T = table()
            %TABLE Machine-readable selected-row catalog.
            T = struct2table(sixgr.phy.frame. ...
                TimeDomainResourceAllocationCatalog.selectedRows());
        end
    end
end

function row = localRow(id, channel, tableNumber, tableProfile, ...
        rowIndex, dmrsTypeAPosition, mu, mappingType, k0, k2, ...
        kExpression, jValue, startSymbol, numSymbols)
symbolsPerSlot = 14;
sliv = sixgr.phy.frame.ResourceAllocationValidator.encodeSLIV( ...
    startSymbol, numSymbols, symbolsPerSlot);
row = struct( ...
    "ID", string(id), ...
    "Channel", string(channel), ...
    "Direction", localDirection(channel), ...
    "TableNumber", string(tableNumber), ...
    "TableProfile", string(tableProfile), ...
    "RowIndex", double(rowIndex), ...
    "CyclicPrefix", "normal", ...
    "SymbolsPerSlot", symbolsPerSlot, ...
    "DMRSTypeAPosition", double(dmrsTypeAPosition), ...
    "Mu", double(mu), ...
    "MappingType", string(mappingType), ...
    "K0", double(k0), ...
    "K2", double(k2), ...
    "KExpression", string(kExpression), ...
    "JValue", double(jValue), ...
    "StartSymbol", double(startSymbol), ...
    "NumSymbols", double(numSymbols), ...
    "SLIV", double(sliv), ...
    "StandardRelease", ...
        sixgr.phy.frame.TimeDomainResourceAllocationCatalog.StandardRelease, ...
    "SpecificationVersion", ...
        sixgr.phy.frame.TimeDomainResourceAllocationCatalog.SpecificationVersion, ...
    "StandardReference", ...
        "3GPP TS 38.214 V18.8.0 Table " + string(tableNumber), ...
    "SpecificationURI", ...
        sixgr.phy.frame.TimeDomainResourceAllocationCatalog.SpecificationURI, ...
    "IndexConvention", "one_based_standard_row_zero_based_phy_symbols", ...
    "SourceKind", "pinned_selected_standard_row");
end

function direction = localDirection(channel)
if string(channel) == "PDSCH"
    direction = "DL";
else
    direction = "UL";
end
end
