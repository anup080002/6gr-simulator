classdef PRACHOccasionResolver
    %PRACHOCCASIONRESOLVER Canonical table/toolbox PRACH timing resolver.
    %
    % The resolver scans exactly one configuration-table repetition period
    % (x radio frames). It never substitutes an A1 format, never treats all
    % slots as active, and never suppresses a Toolbox configuration error.

    methods (Static)
        function result = resolve(varargin)
            p = inputParser;
            p.FunctionName = "sixgr.phy.frame.PRACHOccasionResolver.resolve";
            addParameter(p, "FrequencyRange", "", @localTextScalar);
            addParameter(p, "DuplexMode", "", @localTextScalar);
            addParameter(p, "ConfigurationIndex", NaN, @localFiniteOrNaN);
            addParameter(p, "CarrierSubcarrierSpacingKHz", NaN, @localFiniteOrNaN);
            addParameter(p, "CarrierCyclicPrefix", "normal", @localTextScalar);
            addParameter(p, "NSizeGrid", NaN, @localFiniteOrNaN);
            addParameter(p, "NStartGrid", 0, @localNonnegativeInteger);
            addParameter(p, "NCellID", 0, @localNonnegativeInteger);
            addParameter(p, "PRACHSubcarrierSpacingKHz", NaN, @localFiniteOrNaN);
            addParameter(p, "SequenceIndex", 0, @localNonnegativeInteger);
            addParameter(p, "PreambleIndex", 0, @localNonnegativeInteger);
            addParameter(p, "RestrictedSet", "UnrestrictedSet", @localTextScalar);
            addParameter(p, "ZeroCorrelationZone", 0, @localNonnegativeInteger);
            addParameter(p, "Msg1FDM", 1, @localPositiveInteger);
            addParameter(p, "Msg1FrequencyStart", 0, @localNonnegativeInteger);
            addParameter(p, "RBOffset", 0, @localNonnegativeInteger);
            addParameter(p, "RBSetOffset", 0, @localNonnegativeInteger);
            addParameter(p, "CommonDirection", strings(0, 0));
            addParameter(p, "ResolvedDirection", strings(0, 0));
            parse(p, varargin{:});
            opt = p.Results;

            localRequireToolbox();
            [toolboxRange, rangeSubtype] = ...
                localFrequencyRange(opt.FrequencyRange);
            duplex = upper(strtrim(string(opt.DuplexMode)));
            if toolboxRange == "FR2" && duplex ~= "TDD"
                error("sixgr:phy:frame:InvalidPRACHFrequencyDuplexContext", ...
                    "FR2 PRACH supports unpaired/TDD context only.");
            elseif toolboxRange == "FR1" && ...
                    ~any(duplex == ["FDD", "TDD", "SUL"])
                error("sixgr:phy:frame:InvalidPRACHFrequencyDuplexContext", ...
                    "FR1 PRACH DuplexMode must be FDD, TDD, or SUL.");
            end

            configurationIndex = double(opt.ConfigurationIndex);
            if ~(isfinite(configurationIndex) && ...
                    configurationIndex == fix(configurationIndex) && ...
                    configurationIndex >= 0 && configurationIndex <= 262)
                error("sixgr:phy:frame:InvalidPRACHConfigurationIndex", ...
                    "PRACH ConfigurationIndex must be an integer in [0,262].");
            end
            if (toolboxRange == "FR2" || any(duplex == ["FDD", "SUL"])) && ...
                    configurationIndex > 255
                error("sixgr:phy:frame:InvalidPRACHConfigurationIndex", ...
                    "ConfigurationIndex=%d is unavailable for %s/%s.", ...
                    configurationIndex, rangeSubtype, duplex);
            end
            msg1FDM = double(opt.Msg1FDM);
            if ~any(msg1FDM == [1, 2, 4, 8])
                error("sixgr:phy:frame:InvalidMsg1FDM", ...
                    "msg1-FDM must be 1, 2, 4, or 8.");
            end

            carrier = localCarrier(opt);
            prach = localPRACH(opt, toolboxRange, duplex, configurationIndex);
            tableInfo = localConfigurationTable( ...
                toolboxRange, duplex, configurationIndex);
            periodPRACHSlots = double(prach.PRACHSlotsPerPeriod);
            subframesPerPRACHSlot = double(prach.SubframesPerPRACHSlot);
            periodSubframes = periodPRACHSlots * subframesPerPRACHSlot;
            if ~(isscalar(periodPRACHSlots) && isfinite(periodPRACHSlots) && ...
                    periodPRACHSlots >= 1 && periodPRACHSlots == fix(periodPRACHSlots) && ...
                    isfinite(periodSubframes) && periodSubframes >= 1)
                error("sixgr:phy:frame:InvalidPRACHRepetitionPeriod", ...
                    "The selected PRACH configuration has invalid exact " + ...
                    "PRACHSlotsPerPeriod/SubframesPerPRACHSlot values.");
            end
            baseCarrierSlots = periodSubframes * ...
                localSlotsPerFrame(carrier) / 10;
            if baseCarrierSlots ~= fix(baseCarrierSlots)
                error("sixgr:phy:frame:InvalidPRACHRepetitionPeriod", ...
                    "PRACH repetition period does not map to an integer " + ...
                    "number of carrier slots.");
            end
            directionPeriodSlots = localDirectionPeriodSlots( ...
                string(opt.CommonDirection), string(opt.ResolvedDirection));
            scanCarrierSlots = lcm(uint64(baseCarrierSlots), ...
                uint64(directionPeriodSlots));
            repetitionCount = double(scanCarrierSlots / ...
                uint64(baseCarrierSlots));
            scanPRACHSlots = periodPRACHSlots * repetitionCount;

            occasions = localEnumerateOccasions( ...
                carrier, prach, tableInfo, scanPRACHSlots, msg1FDM, ...
                string(opt.CommonDirection), string(opt.ResolvedDirection));
            if isempty(occasions)
                error("sixgr:phy:frame:NoPRACHOccasionInRepetitionPeriod", ...
                    "ConfigurationIndex=%d produced no PRACH occasion in " + ...
                    "its exact %d-PRACH-slot repetition period.", ...
                    configurationIndex, scanPRACHSlots);
            end

            result = struct( ...
                "ContractVersion", "sixgr_prach_occasion_release18/v1", ...
                "Standard", ...
                    "3GPP TS 38.211 V18.8.0 Tables 6.3.3.2-2 through 6.3.3.2-4", ...
                "IndexConvention", "zero_based_phy_indices", ...
                "FrequencyRange", rangeSubtype, ...
                "ToolboxFrequencyRange", toolboxRange, ...
                "DuplexMode", duplex, ...
                "ConfigurationIndex", configurationIndex, ...
                "Format", string(prach.Format), ...
                "PRACHSubcarrierSpacingKHz", double(prach.SubcarrierSpacing), ...
                "CarrierSubcarrierSpacingKHz", double(carrier.SubcarrierSpacing), ...
                "SequenceLength", double(prach.LRA), ...
                "RestrictedSet", string(prach.RestrictedSet), ...
                "ZeroCorrelationZone", double(prach.ZeroCorrelationZone), ...
                "Msg1FDM", msg1FDM, ...
                "Msg1FrequencyStart", double(prach.FrequencyStart), ...
                "TablePeriodFrames", double(tableInfo.x), ...
                "PeriodFrames", double(scanCarrierSlots) / ...
                    localSlotsPerFrame(carrier), ...
                "BasePeriodFrames", double(periodSubframes / 10), ...
                "PeriodPRACHSlots", scanPRACHSlots, ...
                "BasePeriodPRACHSlots", periodPRACHSlots, ...
                "PeriodCarrierSlots", double(scanCarrierSlots), ...
                "BasePeriodCarrierSlots", double(baseCarrierSlots), ...
                "DirectionPeriodSlots", double(directionPeriodSlots), ...
                "SubframesPerPRACHSlot", subframesPerPRACHSlot, ...
                "TableRow", tableInfo, ...
                "IndependentReferenceValidated", ...
                    logical(sixgr.util.structGet( ...
                    tableInfo, "IndependentReferenceValidated", false)), ...
                "IndependentReferenceMismatchCount", ...
                    double(sixgr.util.structGet( ...
                    tableInfo, "IndependentReferenceMismatchCount", NaN)), ...
                "Occasions", struct2table(occasions), ...
                "ResolvedValid", true, ...
                "FallbackUsed", false, ...
                "UnknownIndexDefaulted", false);
        end

        function result = resolveFromConfig(cfg, varargin)
            args = { ...
                "FrequencyRange", sixgr.util.structGet(cfg, ...
                    "phy.prach.frequencyRange", ...
                    sixgr.util.structGet(cfg, "phy.frequencyRange", "")), ...
                "DuplexMode", sixgr.phy.frame.resolveDuplexMode(cfg), ...
                "ConfigurationIndex", sixgr.util.structGet(cfg, ...
                    "phy.prach.configurationIndex", ...
                    sixgr.util.structGet(cfg, ...
                    "random_access.configuration_index", NaN)), ...
                "CarrierSubcarrierSpacingKHz", sixgr.util.structGet(cfg, ...
                    "phy.carrier.SubcarrierSpacing_kHz", ...
                    sixgr.util.structGet(cfg, ...
                    "phy.carrier.SubcarrierSpacing", NaN)), ...
                "CarrierCyclicPrefix", sixgr.util.structGet(cfg, ...
                    "phy.carrier.CyclicPrefix", "normal"), ...
                "NSizeGrid", sixgr.util.structGet(cfg, ...
                    "phy.carrier.NSizeGrid", NaN), ...
                "NStartGrid", sixgr.util.structGet(cfg, ...
                    "phy.carrier.NStartGrid", 0), ...
                "NCellID", sixgr.util.structGet(cfg, ...
                    "phy.carrier.NCellID", 0), ...
                "PRACHSubcarrierSpacingKHz", sixgr.util.structGet(cfg, ...
                    "phy.prach.subcarrierSpacing_kHz", ...
                    sixgr.util.structGet(cfg, ...
                    "phy.prach.subcarrierSpacingKHz", NaN)), ...
                "SequenceIndex", sixgr.util.structGet(cfg, ...
                    "phy.prach.rootSeqIndex", 0), ...
                "PreambleIndex", sixgr.util.structGet(cfg, ...
                    "phy.prach.preambleIndex", 0), ...
                "RestrictedSet", sixgr.util.structGet(cfg, ...
                    "phy.prach.restrictedSet", "UnrestrictedSet"), ...
                "ZeroCorrelationZone", sixgr.util.structGet(cfg, ...
                    "phy.prach.zeroCorrelationZone", 0), ...
                "Msg1FDM", sixgr.util.structGet(cfg, ...
                    "phy.prach.msg1FDM", 1), ...
                "Msg1FrequencyStart", sixgr.util.structGet(cfg, ...
                    "phy.prach.frequencyStart", 0)};
            result = sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
                args{:}, varargin{:});
        end
    end
end

function localRequireToolbox()
required = ["nrCarrierConfig", "nrPRACHConfig", ...
    "nrPRACH", "nrPRACHIndices"];
for name = required
    if isempty(which(name))
        error("sixgr:phy:frame:PRACHToolboxDependencyMissing", ...
            "Canonical PRACH occasion resolution requires %s.", name);
    end
end
end

function [toolboxRange, subtype] = localFrequencyRange(raw)
subtype = upper(strtrim(string(raw)));
if subtype == "FR2"
    subtype = "FR2-1";
end
if subtype == "FR1"
    toolboxRange = "FR1";
elseif any(subtype == ["FR2-1", "FR2-2"])
    toolboxRange = "FR2";
else
    error("sixgr:phy:frame:UnsupportedFrequencyRange", ...
        "PRACH FrequencyRange must be FR1, FR2-1, or FR2-2.");
end
end

function carrier = localCarrier(opt)
scs = double(opt.CarrierSubcarrierSpacingKHz);
nSizeGrid = double(opt.NSizeGrid);
if ~(isfinite(scs) && scs > 0)
    error("sixgr:phy:frame:InvalidPRACHCarrierSCS", ...
        "CarrierSubcarrierSpacingKHz must be positive and finite.");
end
if ~(isfinite(nSizeGrid) && nSizeGrid >= 1 && nSizeGrid == fix(nSizeGrid))
    error("sixgr:phy:frame:InvalidPRACHCarrierGrid", ...
        "NSizeGrid must be a positive integer.");
end
carrier = nrCarrierConfig;
carrier.SubcarrierSpacing = scs;
carrier.CyclicPrefix = char(string(opt.CarrierCyclicPrefix));
carrier.NSizeGrid = nSizeGrid;
carrier.NStartGrid = double(opt.NStartGrid);
carrier.NCellID = double(opt.NCellID);
carrier.NFrame = 0;
carrier.NSlot = 0;
end

function prach = localPRACH(opt, toolboxRange, duplex, configurationIndex)
scs = double(opt.PRACHSubcarrierSpacingKHz);
if ~(isfinite(scs) && scs > 0)
    error("sixgr:phy:frame:InvalidPRACHSubcarrierSpacing", ...
        "PRACHSubcarrierSpacingKHz must be positive and finite.");
end
prach = nrPRACHConfig;
try
    prach.FrequencyRange = char(toolboxRange);
    prach.DuplexMode = char(duplex);
    prach.ConfigurationIndex = configurationIndex;
    prach.SubcarrierSpacing = scs;
    prach.SequenceIndex = double(opt.SequenceIndex);
    prach.PreambleIndex = double(opt.PreambleIndex);
    prach.RestrictedSet = char(string(opt.RestrictedSet));
    prach.ZeroCorrelationZone = double(opt.ZeroCorrelationZone);
    prach.FrequencyStart = double(opt.Msg1FrequencyStart);
    prach.RBOffset = double(opt.RBOffset);
    prach.RBSetOffset = double(opt.RBSetOffset);
catch cause
    failure = MException("sixgr:phy:frame:InvalidPRACHConfiguration", ...
        "PRACH configuration failed for range=%s duplex=%s index=%d " + ...
        "SCS=%g kHz: %s", ...
        toolboxRange, duplex, configurationIndex, scs, cause.message);
    failure = addCause(failure, cause);
    throwAsCaller(failure);
end
end

function row = localConfigurationTable(toolboxRange, duplex, index)
tables = nrPRACHConfig.Tables;
if toolboxRange == "FR1" && any(duplex == ["FDD", "SUL"])
    tableData = tables.ConfigurationsFR1PairedSUL;
    tableName = "TS_38_211_Table_6_3_3_2_2";
elseif toolboxRange == "FR1"
    tableData = tables.ConfigurationsFR1Unpaired;
    tableName = "TS_38_211_Table_6_3_3_2_3";
else
    tableData = tables.ConfigurationsFR2;
    tableName = "TS_38_211_Table_6_3_3_2_4";
end
selected = find(double(tableData.ConfigurationIndex) == index);
if numel(selected) ~= 1
    error("sixgr:phy:frame:InvalidPRACHConfigurationIndex", ...
        "ConfigurationIndex=%d does not resolve to exactly one %s row.", ...
        index, tableName);
end
t = tableData(selected, :);
variableNames = string(t.Properties.VariableNames);
numberField = variableNames(ismember(variableNames, ...
    ["SubframeNumber", "SlotNumber"]));
slotCountField = variableNames(ismember(variableNames, ...
    ["PRACHSlotsPerSubframe", "PRACHSlotsPer60kHzSlot"]));
if numel(numberField) ~= 1 || numel(slotCountField) ~= 1
    error("sixgr:phy:frame:InvalidPRACHConfigurationTable", ...
        "Configuration table %s does not expose its reference timing fields.", ...
        tableName);
end
row = struct( ...
    "SourceTable", tableName, ...
    "ConfigurationIndex", double(t.ConfigurationIndex), ...
    "PreambleFormat", string(t.PreambleFormat), ...
    "x", double(t.x), ...
    "y", double(localCellValue(t.y)), ...
    "FrameOrSlotNumbers", double(localCellValue(t.(numberField))), ...
    "StartingSymbol", double(t.StartingSymbol), ...
    "PRACHSlotsPerReferenceUnit", double(t.(slotCountField)), ...
    "NumTimeOccasions", double(t.NumTimeOccasions), ...
    "PRACHDuration", double(t.PRACHDuration), ...
    "IndependentReferenceValidated", false, ...
    "IndependentReferenceMismatchCount", NaN, ...
    "IndependentReferenceCatalogSHA256", "", ...
    "IndependentReferenceSourceDocumentSHA256", "");
if toolboxRange == "FR1"
    reference = sixgr.phy.ia.PRACHReferenceCatalog.resolveFR1( ...
        duplex, index);
    mismatch = localReferenceMismatchCount(row, reference);
    if mismatch ~= 0
        error("sixgr:phy:frame:PRACHIndependentReferenceMismatch", ...
            "Toolbox PRACH table row differs from official Release-18 " + ...
            "reference for %s index %d (%d mismatched fields).", ...
            duplex, index, mismatch);
    end
    row.IndependentReferenceValidated = true;
    row.IndependentReferenceMismatchCount = 0;
    row.IndependentReferenceCatalogSHA256 = ...
        reference.CatalogSHA256;
    row.IndependentReferenceSourceDocumentSHA256 = ...
        reference.SourceDocumentSHA256;
end
end

function count = localReferenceMismatchCount(actual, expected)
count = 0;
textFields = ["SourceTable","PreambleFormat"];
for name = textFields
    if string(actual.(name)) ~= string(expected.(name))
        count = count + 1;
    end
end
scalarFields = ["ConfigurationIndex","x","y","StartingSymbol", ...
    "PRACHSlotsPerReferenceUnit","NumTimeOccasions","PRACHDuration"];
for name = scalarFields
    a = double(actual.(name));
    b = double(expected.(name));
    if ~(isequaln(a, b) || ...
            (isscalar(a) && isscalar(b) && ...
            isfinite(a) && isfinite(b) && abs(a - b) < 1e-12))
        count = count + 1;
    end
end
a = sort(double(actual.FrameOrSlotNumbers(:)));
b = sort(double(expected.FrameOrSlotNumbers(:)));
if ~isequaln(a, b)
    count = count + 1;
end
end

function value = localCellValue(value)
if iscell(value)
    value = value{1};
end
end

function rows = localEnumerateOccasions( ...
        carrier, prach, tableInfo, periodPRACHSlots, msg1FDM, ...
        commonDirection, resolvedDirection)
rows = repmat(localEmptyOccasion(), 0, 1);
slotsPerFrame = localSlotsPerFrame(carrier);
ordinal = 0;
activeSlots = localActivePRACHSlots( ...
    double(prach.SubcarrierSpacing), ...
    double(tableInfo.PRACHSlotsPerReferenceUnit));
carrierSlotsPerSubframe = slotsPerFrame / 10;
for prachSlot = 0:(periodPRACHSlots - 1)
    prach.NPRACHSlot = prachSlot;
    if ~localTableSlotActive(prach, tableInfo)
        continue;
    end
    startCarrierSlotExact = prachSlot * ...
        double(prach.SubframesPerPRACHSlot) * carrierSlotsPerSubframe;
    carrierSlot = floor(startCarrierSlotExact);
    carrier.NFrame = floor(carrierSlot / slotsPerFrame);
    carrier.NSlot = mod(carrierSlot, slotsPerFrame);
    for activeIndex = 1:numel(activeSlots)
        activeSlot = activeSlots(activeIndex);
        prach.ActivePRACHSlot = activeSlot;
        numTimeOccasions = double(prach.NumTimeOccasions);
        if ~(isfinite(numTimeOccasions) && numTimeOccasions >= 1 && ...
                numTimeOccasions == fix(numTimeOccasions))
            error("sixgr:phy:frame:InvalidPRACHTimeOccasionCount", ...
                "nrPRACHConfig resolved invalid NumTimeOccasions=%g.", ...
                numTimeOccasions);
        end
        for timeIndex = 0:(numTimeOccasions - 1)
            prach.TimeIndex = timeIndex;
            toolboxStartSymbol = double(prach.SymbolLocation);
            toolboxDuration = double(prach.PRACHDuration);
            [startSymbol, duration] = localCarrierSymbolInterval( ...
                carrier, prach, startCarrierSlotExact, ...
                toolboxStartSymbol, toolboxDuration);
            for frequencyIndex = 0:(msg1FDM - 1)
                prach.FrequencyIndex = frequencyIndex;
                [indices, indexInfo] = localMaterializeToolboxOccasion( ...
                    carrier, prach);
                if isempty(indices)
                    if frequencyIndex == 0
                        % The Toolbox uses NPRACHSlot/ActivePRACHSlot as a
                        % paired gate. An inactive pairing has no frequency
                        % occasions at all.
                        break;
                    end
                    error("sixgr:phy:frame:PRACHFrequencyOccasionOutsideCarrier", ...
                        "ConfigurationIndex=%d frequency occasion %d has " + ...
                        "no carrier-grid indices.", ...
                        double(prach.ConfigurationIndex), frequencyIndex);
                end
                absoluteSlot = carrierSlot;
                occupiedSymbols = unique(double(indices(:, 2))).';
                if isempty(occupiedSymbols) || ...
                        any(diff(occupiedSymbols) ~= 1)
                    error("sixgr:phy:frame:InvalidPRACHCarrierSymbolMapping", ...
                        "nrPRACHIndices returned a non-contiguous carrier " + ...
                        "symbol allocation for index=%d.", ...
                        double(prach.ConfigurationIndex));
                end
                if double(prach.LRA) ~= 839
                    % nrPRACHIndices indexes nrPRACHGrid at PRACH SCS, not
                    % the carrier's time grid. Map the actual CP/useful
                    % sample support, including the fractional-slot origin.
                    sampleTiming=sixgr.rach.prachSampleTiming(carrier,prach);
                    absoluteSlot=sampleTiming.CarrierSlot0;
                    startSymbol=sampleTiming.CarrierStartSymbol;
                    duration=sampleTiming.CarrierDurationSymbols;
                end
                [availability, availabilityReason] = ...
                    localAvailability(absoluteSlot, startSymbol, duration, ...
                    localSymbolsPerSlot(carrier), commonDirection, ...
                    resolvedDirection);
                if availabilityReason == "unresolved_flexible_symbol"
                    error("sixgr:phy:frame:PRACHFlexibleSymbolUnresolved", ...
                        "ConfigurationIndex=%d occasion at slot %d " + ...
                        "requires a flexible symbol that is not resolved UL.", ...
                        double(prach.ConfigurationIndex), absoluteSlot);
                elseif ~availability
                    error("sixgr:phy:frame:PRACHOccasionNotULAvailable", ...
                        "ConfigurationIndex=%d occasion at slot %d " + ...
                        "symbols [%g,%g) is not fully UL-available (%s).", ...
                        double(prach.ConfigurationIndex), absoluteSlot, ...
                        startSymbol, startSymbol + duration, ...
                        availabilityReason);
                end
                ordinal = ordinal + 1;
                row = localEmptyOccasion();
                row.Ordinal = ordinal;
                row.Frame = floor(absoluteSlot / slotsPerFrame);
                row.AbsoluteSlot = absoluteSlot;
                row.SlotWithinFrame = mod(absoluteSlot, slotsPerFrame);
                row.PRACHSlot = prachSlot;
                row.ActivePRACHSlot = activeSlot;
                row.TimeIndex = timeIndex;
                row.FrequencyIndex = frequencyIndex;
                row.Format = string(prach.Format);
                row.StartSymbol = startSymbol;
                row.DurationSymbols = duration;
                row.ToolboxSymbolLocation = toolboxStartSymbol;
                row.ToolboxPRACHDuration = toolboxDuration;
                % RA-RNTI coordinates live on the PRACH/reference clock,
                % not on the data-carrier numerology. TS 38.321 5.1.3 caps
                % t_id at the containing 120-kHz slot for 480/960 kHz.
                if double(prach.LRA)==839
                    pi=nrPRACHOFDMInfo(carrier,prach,'Windowing',0);
                    activeStart=prachSlot*double(prach.SubframesPerPRACHSlot)*1e-3+double(pi.OffsetLength)/double(pi.SampleRate);
                    referenceSCS=15;
                    sid=double(tableInfo.StartingSymbol);
                else
                    activeStart=sampleTiming.ActiveStartTime_s;
                    referenceSCS=min(double(prach.SubcarrierSpacing),120);
                    sid=toolboxStartSymbol;
                    if string(prach.Format)=="C0", sid=2*sid; end
                    sid=mod(sid,14);
                end
                referenceSlot=activeStart/(1e-3*15/referenceSCS);
                row.RARNTISymbolIndex=sid;
                row.RARNTISlotIndex=mod(floor(referenceSlot+16*eps(max(1,referenceSlot))),10*referenceSCS/15);
                if ~isfield(indexInfo, "PRBSet") || isempty(indexInfo.PRBSet)
                    error("sixgr:phy:frame:InvalidPRACHFrequencyMapping", ...
                        "nrPRACHIndices did not return its carrier PRB set.");
                end
                row.FrequencyStart = min(double(indexInfo.PRBSet));
                row.ConfiguredFrequencyStart = ...
                    double(prach.FrequencyStart);
                row.PRBCount = numel(unique(double(indexInfo.PRBSet)));
                row.IndexCount = size(indices, 1);
                row.SymbolCount = size(indices, 1);
                row.ULAvailable = availability;
                row.AvailabilityReason = availabilityReason;
                rows(end + 1, 1) = row; %#ok<AGROW>
            end
        end
    end
end
end

function active = localTableSlotActive(prach, tableInfo)
% Fast exact table predicate before the more expensive Toolbox materializer.
% Long-preamble periods are already small and retain Toolbox-only gating.
if double(prach.LRA) == 839
    active = true;
    return;
end
if string(prach.FrequencyRange) == "FR1"
    referenceSCS = 15;
    referenceSlotsPerFrame = 10;
else
    referenceSCS = 60;
    referenceSlotsPerFrame = 40;
end
referenceAbsoluteSlot = floor(double(prach.NPRACHSlot) * ...
    referenceSCS / double(prach.SubcarrierSpacing));
referenceFrame = floor(referenceAbsoluteSlot / referenceSlotsPerFrame);
referenceSlot = mod(referenceAbsoluteSlot, referenceSlotsPerFrame);
active = any(referenceSlot == double(tableInfo.FrameOrSlotNumbers)) && ...
    any(mod(referenceFrame, double(tableInfo.x)) == double(tableInfo.y));
end

function [startSymbol, duration] = localCarrierSymbolInterval( ...
        carrier, prach, startCarrierSlotExact, ...
        toolboxStartSymbol, toolboxDuration)
symbolsPerSlot = localSymbolsPerSlot(carrier);
fractionalCarrierSlot = startCarrierSlotExact - floor(startCarrierSlotExact);
slotOffsetSymbols = fractionalCarrierSlot * symbolsPerSlot;
if double(prach.LRA) == 839
    startSymbol = slotOffsetSymbols;
    duration = double(prach.SubframesPerPRACHSlot) * ...
        localSlotsPerFrame(carrier) / 10 * symbolsPerSlot;
else
    scale = double(carrier.SubcarrierSpacing) / ...
        double(prach.SubcarrierSpacing);
    startSymbol = mod(slotOffsetSymbols + ...
        toolboxStartSymbol * scale, symbolsPerSlot);
    duration = toolboxDuration * scale;
end
if ~(isfinite(startSymbol) && isfinite(duration) && ...
        startSymbol >= 0 && duration > 0)
    error("sixgr:phy:frame:InvalidPRACHCarrierSymbolInterval", ...
        "PRACH occasion cannot be mapped onto the carrier symbol timeline.");
end
end

function count = localSymbolsPerSlot(carrier)
numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
    double(carrier.SubcarrierSpacing), string(carrier.CyclicPrefix), ...
    "generic_waveform_test", "");
count = double(numerology.SymbolsPerSlot);
end

function [indices, info] = localMaterializeToolboxOccasion(carrier, prach)
try
    [indices, info] = nrPRACHIndices(carrier, prach, ...
        "IndexStyle", "subscript", "IndexBase", "0based");
catch cause
    failure = MException("sixgr:phy:frame:PRACHToolboxResolutionFailed", ...
        "nrPRACHIndices failed for index=%d frame=%d slot=%d " + ...
        "timeIndex=%d frequencyIndex=%d: %s", ...
        double(prach.ConfigurationIndex), double(carrier.NFrame), ...
        double(carrier.NSlot), double(prach.TimeIndex), ...
        double(prach.FrequencyIndex), cause.message);
    failure = addCause(failure, cause);
    throwAsCaller(failure);
end
end

function active = localActivePRACHSlots(prachSCS, slotsPerReferenceUnit)
if ~any(prachSCS == [30, 120, 480, 960])
    active = 0;
    return;
elseif any(prachSCS == [30, 120])
    active = [0, 1];
elseif prachSCS == 480
    active = [3, 7];
elseif prachSCS == 960
    active = [7, 15];
else
    error("sixgr:phy:frame:UnsupportedActivePRACHSlotSet", ...
        "PRACH SCS %g kHz has no supported active-slot set.", prachSCS);
end
if isfinite(slotsPerReferenceUnit) && slotsPerReferenceUnit == 1 && ...
        numel(active) == 2
    active = active(2);
elseif isfinite(slotsPerReferenceUnit) && ...
        slotsPerReferenceUnit ~= numel(active)
    error("sixgr:phy:frame:PRACHActiveSlotCountMismatch", ...
        "Table requests %g active slots but PRACH SCS %g kHz resolves %d.", ...
        slotsPerReferenceUnit, prachSCS, numel(active));
end
end

function [available, reason] = localAvailability( ...
        absoluteSlot, startSymbol, duration, symbolsPerSlot, common, resolved)
available = true;
reason = "not_applicable_or_ul_available";
if isempty(common) && isempty(resolved)
    return;
end
first = floor(startSymbol);
last = ceil(startSymbol + duration) - 1;
if first < 0
    error("sixgr:phy:frame:InvalidPRACHOccasionSymbols", ...
        "PRACH SymbolLocation must not be negative.");
end
for absoluteSymbol = first:last
    slotOffset = floor(absoluteSymbol / symbolsPerSlot);
    symbolOneBased = mod(absoluteSymbol, symbolsPerSlot) + 1;
    mappedSlot = absoluteSlot + slotOffset;
    commonValue = localDirectionAt(common, mappedSlot, symbolOneBased);
    resolvedValue = localDirectionAt(resolved, mappedSlot, symbolOneBased);
    if any(upper(commonValue) == ["D", "DL"])
        available = false;
        reason = "fixed_dl_symbol";
        return;
    end
    if any(upper(commonValue) == ["F", "FLEXIBLE"]) && ...
            ~any(upper(resolvedValue) == ["U", "UL"])
        available = false;
        reason = "unresolved_flexible_symbol";
        return;
    end
    if strlength(resolvedValue) > 0 && ...
            ~any(upper(resolvedValue) == ["U", "UL"])
        available = false;
        reason = "resolved_non_ul_symbol";
        return;
    end
end
end

function value = localDirectionAt(map, absoluteSlot, symbolOneBased)
value = "";
if isempty(map)
    return;
end
if isvector(map)
    if symbolOneBased <= numel(map)
        value = string(map(symbolOneBased));
    end
elseif size(map, 1) > 0 && symbolOneBased <= size(map, 2)
    row = mod(absoluteSlot, size(map, 1)) + 1;
    value = string(map(row, symbolOneBased));
end
end

function slots = localSlotsPerFrame(carrier)
scs = double(carrier.SubcarrierSpacing);
cp = string(sixgr.util.structGet(carrier, "CyclicPrefix", "normal"));
numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
    scs, cp, "generic_waveform_test", "");
slots = double(numerology.SlotsPerFrame);
end

function period = localDirectionPeriodSlots(common, resolved)
period = 1;
for map = {common, resolved}
    value = map{1};
    if isempty(value) || isvector(value)
        candidate = 1;
    else
        candidate = size(value, 1);
    end
    if candidate < 1 || candidate ~= fix(candidate)
        error("sixgr:phy:frame:InvalidDirectionMapPeriod", ...
            "A PRACH direction map must contain a positive integer " + ...
            "number of carrier-slot rows.");
    end
    period = double(lcm(uint64(period), uint64(candidate)));
end
end

