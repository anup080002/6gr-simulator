classdef ChannelAllocationMaterializer
    %CHANNELALLOCATIONMATERIALIZER Toolbox-backed exact RE allocation objects.
    %
    % The returned Allocation fields are canonical
    % ResourceAllocationValidator inputs.  They contain exact zero-based
    % [subcarrier symbol port] coordinates generated from Toolbox indices;
    % no rectangular approximation is presented as actual occupancy.

    methods (Static)
        function result = materializePDCCH(carrier, pdcch, varargin)
            localRequireObject(carrier, "nrCarrierConfig", "carrier");
            localRequireObject(pdcch, "nrPDCCHConfig", "pdcch");
            opt = localOptions(carrier, varargin{:});
            [dataIndices, ~, dmrsIndices] = ...
                nrPDCCHResources(carrier, pdcch);
            data = localLinearComponent( ...
                carrier, dataIndices, "PDCCH_DATA", ...
                "nrPDCCHResources:data", opt);
            dmrs = localLinearComponent( ...
                carrier, dmrsIndices, "PDCCH_DMRS", ...
                "nrPDCCHResources:dmrs", opt);
            actualCoordinates = unique( ...
                [data.Coordinates0Based; dmrs.Coordinates0Based], ...
                "rows", "stable");
            if isempty(actualCoordinates)
                error("sixgr:phy:frame:EmptyToolboxAllocation", ...
                    "nrPDCCHResources returned no PDCCH candidate RE.");
            end
            coreset = localCORESETMonitoring(carrier, pdcch, opt);
            allocation = localAllocation( ...
                "PDCCH", "DL", actualCoordinates, ...
                coreset.StartRB, coreset.NumRB, ...
                coreset.StartSymbol, coreset.NumSymbols, "", opt, ...
                strings(0, 1), strings(0, 1), "");
            result = localResult("PDCCH", "nrPDCCHResources", ...
                allocation, actualCoordinates, opt);
            result.CORESETMonitoringOccasion = coreset;
            result.CORESETAllocation = coreset.Allocation;
            result.CandidateAllocation = allocation;
            result.Data = data;
            result.DMRS = dmrs;
        end

        function result = materializePDSCH(carrier, pdsch, varargin)
            localRequireObject(carrier, "nrCarrierConfig", "carrier");
            localRequireObject(pdsch, "nrPDSCHConfig", "pdsch");
            opt = localOptions(carrier, varargin{:});
            [dataIndices, dataInfo] = nrPDSCHIndices( ...
                carrier, pdsch, "IndexStyle", "index", ...
                "IndexBase", "1based", "IndexOrientation", "carrier");
            dmrsIndices = nrPDSCHDMRSIndices( ...
                carrier, pdsch, "IndexStyle", "index", ...
                "IndexBase", "1based", "IndexOrientation", "carrier");
            ptrsIndices = zeros(0, 1);
            if isprop(pdsch, "EnablePTRS") && logical(pdsch.EnablePTRS)
                ptrsIndices = nrPDSCHPTRSIndices( ...
                    carrier, pdsch, "IndexStyle", "index", ...
                    "IndexBase", "1based", "IndexOrientation", "carrier");
            end
            [reservedIndices, reservationDomain] = ...
                localPDSCHReservedIndices(carrier, pdsch, dataInfo);
            data = localLinearComponent(carrier, dataIndices, ...
                "PDSCH_DATA", "nrPDSCHIndices", opt);
            dmrs = localLinearComponent(carrier, dmrsIndices, ...
                "PDSCH_DMRS", "nrPDSCHDMRSIndices", opt);
            ptrs = localLinearComponent(carrier, ptrsIndices, ...
                "PDSCH_PTRS", "nrPDSCHPTRSIndices", opt);
            reserved = localLinearComponent(carrier, reservedIndices, ...
                "PDSCH_RESERVED_RE", "nrPDSCHConfig.ReservedRE", opt);
            actualCoordinates = unique([data.Coordinates0Based; ...
                dmrs.Coordinates0Based; ptrs.Coordinates0Based], ...
                "rows", "stable");
            candidateCoordinates = unique([actualCoordinates; ...
                reserved.Coordinates0Based], "rows", "stable");
            if isempty(actualCoordinates)
                error("sixgr:phy:frame:EmptyToolboxAllocation", ...
                    "PDSCH Toolbox functions returned no occupied RE.");
            end
            actualKeys = localKeys(actualCoordinates, opt);
            reservedKeys = localKeys(reserved.Coordinates0Based, opt);
            if ~isempty(intersect(actualKeys, reservedKeys))
                error("sixgr:phy:frame:PDSCHReservedRECollision", ...
                    "nrPDSCHIndices/DMRS/PTRS still occupy an RE in " + ...
                    "nrPDSCHConfig.ReservedRE.");
            end
            [startRB, numRB] = localCoordinatePRBEnvelope(candidateCoordinates);
            symbolAllocation = localSymbolAllocation(pdsch);
            mappingType = upper(string(pdsch.MappingType));
            allocation = localAllocation( ...
                "PDSCH", "DL", candidateCoordinates, startRB, numRB, ...
                symbolAllocation(1), symbolAllocation(2), mappingType, opt, ...
                reservedKeys, reservedKeys, ...
                localReservedReason(reservedKeys, ...
                "nrPDSCHConfig.ReservedRE"));
            result = localResult("PDSCH", ...
                "nrPDSCHIndices+nrPDSCHDMRSIndices+nrPDSCHPTRSIndices", ...
                allocation, actualCoordinates, opt);
            result.Data = data;
            result.DMRS = dmrs;
            result.PTRS = ptrs;
            result.Reserved = reserved;
            result.IndicesInfo = dataInfo;
            result.ActualREKeys = actualKeys;
            result.RateMatchProof = struct( ...
                "Source", "nrPDSCHConfig.ReservedRE", ...
                "ReservedREIndexBase", "zero_based_toolbox_input", ...
                "ReservedREIndexDomain", "bwp_resource_grid", ...
                "OriginalReservedRE0Based", double(pdsch.ReservedRE), ...
                "MaterializedIndexBase", "one_based_toolbox_output", ...
                "MaterializedIndexDomain", "carrier_resource_grid", ...
                "ReservationDomain", reservationDomain, ...
                "ReservedIndices1Based", reserved.Indices1Based, ...
                "ReservedREKeys", reservedKeys, ...
                "NoOccupiedReservedRECollision", ...
                    isempty(intersect(actualKeys, reservedKeys)), ...
                "ToolboxDataExcludesReservedRE", ...
                    isempty(intersect(data.REKeys, reservedKeys)), ...
                "ToolboxDMRSExcludesReservedRE", ...
                    isempty(intersect(dmrs.REKeys, reservedKeys)), ...
                "ToolboxPTRSExcludesReservedRE", ...
                    isempty(intersect(ptrs.REKeys, reservedKeys)), ...
                "Exact", true);
        end

        function result = materializePUSCH(carrier, pusch, varargin)
            localRequireObject(carrier, "nrCarrierConfig", "carrier");
            localRequireObject(pusch, "nrPUSCHConfig", "pusch");
            opt = localOptions(carrier, varargin{:});
            [dataIndices, dataInfo] = nrPUSCHIndices( ...
                carrier, pusch, "IndexStyle", "index", ...
                "IndexBase", "1based", "IndexOrientation", "carrier");
            dmrsIndices = nrPUSCHDMRSIndices( ...
                carrier, pusch, "IndexStyle", "index", ...
                "IndexBase", "1based", "IndexOrientation", "carrier");
            transformPrecoding = logical(pusch.TransformPrecoding);
            ptrsIndices = zeros(0, 1);
            nativePTRSIndices = zeros(0, 1);
            if isprop(pusch, "EnablePTRS") && logical(pusch.EnablePTRS)
                nativePTRSIndices = nrPUSCHPTRSIndices( ...
                    carrier, pusch, "IndexStyle", "index", ...
                    "IndexBase", "1based");
                ptrsIndices = sixgr.phy.resource.puschPTRSGridIndices( ...
                    carrier, pusch, "IndexBase", "1based");
            end
            embeddedPTRS = transformPrecoding && ~isempty(ptrsIndices);
            dataLabel = "PUSCH_DATA";
            if embeddedPTRS, dataLabel = "PUSCH_TRANSFORMED_DATA_AND_PTRS"; end
            data = localLinearComponent(carrier, dataIndices, ...
                dataLabel, "nrPUSCHIndices", opt);
            dmrs = localLinearComponent(carrier, dmrsIndices, ...
                "PUSCH_DMRS", "nrPUSCHDMRSIndices", opt);
            ptrs = localLinearComponent(carrier, ptrsIndices, ...
                "PUSCH_PTRS", "nrPUSCHPTRSIndices+puschPTRSGridIndices", opt);
            % Keep ordered native matrices separate from occupancy sets.
            % TS 38.211 V18.8.0 6.3.1.4/6.4.1.2.2.2 inserts PT-RS
            % before the DFT. Its projected addresses bind nrPUSCH's extra
            % output to existing transformed values, not isolated pilots.
            data.GridIndices1Based = double(dataIndices);
            data.IndexDomain = "carrier_resource_grid";
            ptrs.NativeIndices1Based = double(nativePTRSIndices);
            ptrs.GridIndices1Based = double(ptrsIndices);
            ptrs.NativeIndexDomain = "carrier_resource_grid";
            ptrs.IndexDomain = "carrier_resource_grid";
            ptrs.EmbeddedInData = embeddedPTRS;
            ptrs.IndependentPhysicalOccupancy = ~transformPrecoding;
            coordinates = [data.Coordinates0Based; dmrs.Coordinates0Based];
            if transformPrecoding
                ptrs.NativeIndexDomain = "pre_transform_pusch_allocation_relative";
                ptrs.IndexDomain = "carrier_grid_projected_allocation_rows";
                assert(all(ismember(ptrsIndices(:), dataIndices(:))), ...
                    "sixgr:phy:frame:EmbeddedPUSCHPTRSOutsideAllocation", ...
                    "Projected DFT PT-RS must be inside its transformed PUSCH allocation.");
            else
                coordinates = [coordinates; ptrs.Coordinates0Based];
            end
            coordinates = unique(coordinates, "rows", "stable");
            % Native coordinates already contain the BWP offset and both
            % frequency hops. PRBSet alone is BWP-relative and first-hop only.
            [startRB, numRB] = localCoordinatePRBEnvelope(coordinates);
            symbolAllocation = localSymbolAllocation(pusch);
            allocation = localAllocation( ...
                "PUSCH", "UL", coordinates, startRB, numRB, ...
                symbolAllocation(1), symbolAllocation(2), ...
                upper(string(pusch.MappingType)), opt, ...
                strings(0, 1), strings(0, 1), "");
            result = localResult("PUSCH", ...
                "nrPUSCHIndices+nrPUSCHDMRSIndices+nrPUSCHPTRSIndices", ...
                allocation, coordinates, opt);
            result.Data = data;
            result.DMRS = dmrs;
            result.PTRS = ptrs;
            result.IndicesInfo = dataInfo;
            result.TransformPrecoding = transformPrecoding;
        end

        function result = materializePUCCH(carrier, pucch, varargin)
            localRequireObject(carrier, "nrCarrierConfig", "carrier");
            if ~startsWith(class(pucch), "nrPUCCH")
                error("sixgr:phy:frame:InvalidToolboxAllocationObject", ...
                    "pucch must be an nrPUCCH*Config object.");
            end
            opt = localOptions(carrier, varargin{:});
            [dataIndices, dataInfo] = nrPUCCHIndices(carrier, pucch);
            dmrsIndices = zeros(0, 1);
            try
                dmrsIndices = nrPUCCHDMRSIndices(carrier, pucch);
            catch cause
                if ~isa(pucch, "nrPUCCH0Config")
                    rethrow(cause);
                end
            end
            data = localLinearComponent(carrier, dataIndices, ...
                "PUCCH_DATA", "nrPUCCHIndices", opt);
            dmrs = localLinearComponent(carrier, dmrsIndices, ...
                "PUCCH_DMRS", "nrPUCCHDMRSIndices", opt);
            coordinates = unique([data.Coordinates0Based; ...
                dmrs.Coordinates0Based], "rows", "stable");
            if isempty(coordinates)
                error("sixgr:phy:frame:EmptyToolboxAllocation", ...
                    "PUCCH Toolbox functions returned no occupied RE.");
            end
            allocation = localAllocationFromCoordinates( ...
                "PUCCH", "UL", coordinates, "", opt);
            result = localResult("PUCCH", ...
                "nrPUCCHIndices+nrPUCCHDMRSIndices", ...
                allocation, coordinates, opt);
            result.Data = data;
            result.DMRS = dmrs;
            result.IndicesInfo = dataInfo;
        end

        function result = materializePRACH(carrier, prach, varargin)
            localRequireObject(carrier, "nrCarrierConfig", "carrier");
            localRequireObject(prach, "nrPRACHConfig", "prach");
            opt = localOptions(carrier, varargin{:});
            [coordinates, indexInfo] = nrPRACHIndices( ...
                carrier, prach, "IndexStyle", "subscript", ...
                "IndexBase", "0based");
            coordinates = double(coordinates);
            if size(coordinates, 2) == 2
                coordinates(:, 3) = 0;
            end
            if isempty(coordinates) || size(coordinates, 2) ~= 3
                error("sixgr:phy:frame:EmptyToolboxAllocation", ...
                    "nrPRACHIndices returned no active native PRACH-grid RE.");
            end
            coordinates = unique(coordinates, "rows", "stable");
            component = localCoordinateComponent(coordinates, ...
                "PRACH", "nrPRACHIndices:subscript_0based", opt);
            % PRACH bins/symbols do not define carrier PRBs/OFDM symbols.
            % No ResourceAllocationValidator carrier envelope may be made
            % from these native indices, even when both SCS values match.
            allocation = struct('GridDomain',"prach_native_ofdm", ...
                'NativeCoordinates0Based',coordinates, ...
                'NativeSubcarrierSpacingHz',1000*double(prach.SubcarrierSpacing));
            result = localResult("PRACH", "nrPRACHIndices", ...
                allocation, coordinates, opt);
            result.Resources = component;
            result.IndicesInfo = indexInfo;
            result.GridDomain="prach_native_ofdm";
            nativeGrid=nrPRACHGrid(carrier,prach);
            result.NativeGridSubcarrierSpacingHz=1000*double(prach.SubcarrierSpacing);
            result.NativeGridSubcarrierCount=size(nativeGrid,1);
            result.NativeGridSymbolCount=size(nativeGrid,2);
        end

        function result = materializeReferenceSignal( ...
                carrier, kind, configObject, varargin)
            localRequireObject(carrier, "nrCarrierConfig", "carrier");
            opt = localOptions(carrier, varargin{:});
            kind = upper(strrep(strtrim(string(kind)), "-", "_"));
            switch kind
                case "PDSCH_DMRS"
                    indices = nrPDSCHDMRSIndices(carrier, configObject);
                    source = "nrPDSCHDMRSIndices";
                    direction = "DL";
                case "PDSCH_PTRS"
                    indices = nrPDSCHPTRSIndices(carrier, configObject);
                    source = "nrPDSCHPTRSIndices";
                    direction = "DL";
                case "PUSCH_DMRS"
                    indices = nrPUSCHDMRSIndices(carrier, configObject);
                    source = "nrPUSCHDMRSIndices";
                    direction = "UL";
                case "PUSCH_PTRS"
                    localRequireObject(configObject, "nrPUSCHConfig", "pusch");
                    assert(~logical(configObject.TransformPrecoding), ...
                        "sixgr:phy:frame:EmbeddedPUSCHPTRSRequiresCombinedAllocation", ...
                        "DFT-spread PT-RS has no isolated frequency-domain pilot allocation. " + ...
                        "Use materializePUSCH for its combined physical occupancy.");
                    indices = sixgr.phy.resource.puschPTRSGridIndices(carrier, configObject);
                    source = "nrPUSCHPTRSIndices+puschPTRSGridIndices";
                    direction = "UL";
                case "PUCCH_DMRS"
                    indices = nrPUCCHDMRSIndices(carrier, configObject);
                    source = "nrPUCCHDMRSIndices";
                    direction = "UL";
                case {"CSI_RS", "CSIRS"}
                    indices = nrCSIRSIndices(carrier, configObject);
                    source = "nrCSIRSIndices";
                    direction = "DL";
                    kind = "CSI_RS";
                case "SRS"
                    indices = nrSRSIndices(carrier, configObject);
                    source = "nrSRSIndices";
                    direction = "UL";
                otherwise
                    error("sixgr:phy:frame:UnsupportedReferenceSignalKind", ...
                        "Unsupported exact reference-signal kind '%s'.", kind);
            end
            component = localLinearComponent( ...
                carrier, indices, kind, source, opt);
            if isempty(component.Coordinates0Based)
                error("sixgr:phy:frame:EmptyToolboxAllocation", ...
                    "%s returned no active reference-signal RE.", source);
            end
            allocation = localAllocationFromCoordinates( ...
                kind, direction, component.Coordinates0Based, "", opt);
            result = localResult(kind, source, allocation, ...
                component.Coordinates0Based, opt);
            result.Resources = component;
        end
    end
end

function opt = localOptions(carrier, varargin)
p = inputParser;
p.FunctionName = "sixgr.phy.frame.ChannelAllocationMaterializer";
addParameter(p, "CCID", 0, @localNonnegativeInteger);
addParameter(p, "BWPID", 0, @localNonnegativeInteger);
addParameter(p, "AbsoluteSlot", localCarrierSlot(carrier), ...
    @localNonnegativeInteger);
addParameter(p, "GridID", "cc0_bwp0_grid", ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));
addParameter(p, "TestID", "", ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));
parse(p, varargin{:});
opt = p.Results;
opt.GridID = strtrim(string(opt.GridID));
opt.TestID = strtrim(string(opt.TestID));
if strlength(opt.GridID) == 0
    error("sixgr:phy:frame:MissingGridIdentity", ...
        "Exact allocation materialization requires a nonempty GridID.");
end
end

function result = localResult(channel, source, allocation, coordinates, opt)
result = struct( ...
    "ContractVersion", "sixgr_exact_channel_allocation/v1", ...
    "Channel", string(channel), ...
    "ToolboxSource", string(source), ...
    "IndexConvention", "one_based_toolbox_zero_based_coordinates", ...
    "GridID", opt.GridID, ...
    "AbsoluteSlot", double(opt.AbsoluteSlot), ...
    "Allocation", allocation, ...
    "ActualCoordinates0Based", coordinates, ...
    "ActualREKeys", localKeys(coordinates, opt), ...
    "Exact", true, ...
    "FallbackUsed", false);
end

function component = localLinearComponent( ...
        carrier, indices, label, source, opt)
indices = unique(double(indices(:)), "stable");
coordinates = localLinearToCoordinates(carrier, indices);
component = localCoordinateComponent(coordinates, label, source, opt);
component.Indices1Based = indices;
end

function component = localCoordinateComponent( ...
        coordinates, label, source, opt)
coordinates = double(coordinates);
if isempty(coordinates)
    coordinates = zeros(0, 3);
end
if size(coordinates, 2) ~= 3 || ...
        any(~isfinite(coordinates), "all") || ...
        any(coordinates < 0, "all") || ...
        any(coordinates ~= fix(coordinates), "all")
    error("sixgr:phy:frame:InvalidToolboxAllocationCoordinates", ...
        "%s did not materialize zero-based integer [subcarrier symbol port] coordinates.", ...
        source);
end
component = struct( ...
    "Label", string(label), ...
    "ToolboxSource", string(source), ...
    "Coordinates0Based", coordinates, ...
    "REKeys", localKeys(coordinates, opt), ...
    "RECount", size(coordinates, 1), ...
    "Indices1Based", zeros(0, 1), ...
    "Exact", true);
end

function coordinates = localLinearToCoordinates(carrier, indices)
if isempty(indices)
    coordinates = zeros(0, 3);
    return;
end
if any(indices < 1) || any(indices ~= fix(indices))
    error("sixgr:phy:frame:InvalidToolboxAllocationIndex", ...
        "Toolbox linear indices must be positive one-based integers.");
end
nSubcarriers = 12 * double(carrier.NSizeGrid);
numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
    double(carrier.SubcarrierSpacing), string(carrier.CyclicPrefix), ...
    "generic_waveform_test", "");
nSymbols = double(numerology.SymbolsPerSlot);
pageSize = nSubcarriers * nSymbols;
nPorts = max(1, ceil(max(indices) / pageSize));
if any(indices > pageSize * nPorts)
    error("sixgr:phy:frame:ToolboxAllocationIndexOutOfRange", ...
        "Toolbox allocation index exceeds the derived carrier-grid shape.");
end
[subcarrier, symbol, port] = ind2sub( ...
    [nSubcarriers nSymbols nPorts], indices);
coordinates = [subcarrier(:) - 1, symbol(:) - 1, port(:) - 1];
coordinates = unique(coordinates, "rows", "stable");
end

function allocation = localAllocationFromCoordinates( ...
        channel, direction, coordinates, mappingType, opt)
startRB = floor(min(coordinates(:, 1)) / 12);
lastRB = floor(max(coordinates(:, 1)) / 12);
startSymbol = min(coordinates(:, 2));
lastSymbol = max(coordinates(:, 2));
allocation = localAllocation(channel, direction, coordinates, ...
    startRB, lastRB - startRB + 1, startSymbol, ...
    lastSymbol - startSymbol + 1, mappingType, opt, ...
    strings(0, 1), strings(0, 1), "");
end

function allocation = localAllocation( ...
        channel, direction, coordinates, startRB, numRB, ...
        startSymbol, numSymbols, mappingType, opt, ...
        rateMatchedKeys, reservedKeys, reservedReason)
ports = unique(coordinates(:, 3), "stable").';
allocation = sixgr.phy.frame.ResourceAllocationValidator.makeAllocation( ...
    channel, direction, ...
    "CCID", double(opt.CCID), "BWPID", double(opt.BWPID), ...
    "AbsoluteSlot", double(opt.AbsoluteSlot), ...
    "StartSymbol", double(startSymbol), ...
    "NumSymbols", double(numSymbols), ...
    "MappingType", string(mappingType), ...
    "StartRB", double(startRB), "NumRB", double(numRB), ...
    "RECoordinates", coordinates, "Ports", ports, ...
    "RateMatchedREKeys", rateMatchedKeys, ...
    "ReservedREKeys", reservedKeys, ...
    "ReservedReason", string(reservedReason), ...
    "GridID", opt.GridID, "TestID", opt.TestID);
end

function monitoring = localCORESETMonitoring(carrier, pdcch, opt)
coreset = pdcch.CORESET;
searchSpace = pdcch.SearchSpace;
frequencyResources = double(coreset.FrequencyResources(:).');
if isempty(frequencyResources) || ...
        any(~ismember(frequencyResources, [0 1]))
    error("sixgr:phy:frame:InvalidCORESETFrequencyResources", ...
        "nrCORESETConfig.FrequencyResources must be a nonempty binary bitmap.");
end
duration = double(coreset.Duration);
startSymbol = double(searchSpace.StartSymbolWithinSlot);
if ~(isscalar(duration) && isfinite(duration) && ...
        duration >= 1 && duration <= 3 && duration == fix(duration))
    error("sixgr:phy:frame:InvalidCORESETDuration", ...
        "Toolbox CORESET duration must be an integer in [1,3].");
end
nStartBWP = localObjectValue(pdcch, "NStartBWP", ...
    double(carrier.NStartGrid));
nSizeBWP = localObjectValue(pdcch, "NSizeBWP", ...
    double(carrier.NSizeGrid));
if isempty(nStartBWP), nStartBWP = double(carrier.NStartGrid); end
if isempty(nSizeBWP), nSizeBWP = double(carrier.NSizeGrid); end
localStartBWP = double(nStartBWP) - double(carrier.NStartGrid);
% Match native CORESET bitmap placement, not only the BWP origin. For
% nonzero CORESET IDs the empty RBOffset aligns the first bitmap group
% to the next six-CRB boundary. An explicit RBOffset replaces alignment.
% CORESET0 ignores RBOffset and starts at the BWP anchor.
bitmapRBOffset = 0;
if double(coreset.CORESETID) ~= 0
    bitmapRBOffset = localObjectValue(coreset, "RBOffset", []);
    if isempty(bitmapRBOffset)
        bitmapRBOffset = 6*ceil(double(nStartBWP)/6)-double(nStartBWP);
    end
end
activeGroups = find(frequencyResources == 1) - 1;
rbSet = zeros(1, 6 * numel(activeGroups));
cursor = 1;
for group = activeGroups
    rbSet(cursor:(cursor + 5)) = ...
        localStartBWP + double(bitmapRBOffset) + group * 6 + (0:5);
    cursor = cursor + 6;
end
if isempty(rbSet) || any(rbSet < 0) || ...
        any(rbSet >= double(carrier.NSizeGrid)) || ...
        any(rbSet < localStartBWP) || ...
        any(rbSet >= localStartBWP + double(nSizeBWP))
    error("sixgr:phy:frame:CORESETFrequencyResourcesOutOfBWP", ...
        "The configured CORESET frequency bitmap exceeds its BWP/carrier grid.");
end
symbols = startSymbol + (0:(duration - 1));
if any(symbols < 0) || any(symbols >= localSymbolsPerSlot(carrier))
    error("sixgr:phy:frame:CORESETSymbolsOutOfSlot", ...
        "The configured CORESET monitoring symbols exceed the carrier slot.");
end
[sc, sym, port] = ndgrid( ...
    reshape(rbSet * 12 + (0:11).', 1, []), symbols, 0);
coordinates = [sc(:), sym(:), port(:)];
allocation = localAllocation("CORESET", "DL", coordinates, ...
    min(rbSet), max(rbSet) - min(rbSet) + 1, ...
    startSymbol, duration, "", opt, ...
    strings(0, 1), strings(0, 1), "");
monitoring = struct( ...
    "CORESETID", double(localObjectValue( ...
        coreset, "CORESETID", 0)), ...
    "SearchSpaceID", double(localObjectValue( ...
        searchSpace, "SearchSpaceID", 0)), ...
    "StartSymbol", startSymbol, ...
    "NumSymbols", duration, ...
    "FrequencyResourceBitmap", frequencyResources, ...
    "BitmapRBOffsetWithinBWP", double(bitmapRBOffset), ...
    "RBSet", rbSet, ...
    "StartRB", min(rbSet), ...
    "NumRB", max(rbSet) - min(rbSet) + 1, ...
    "MonitoringSymbols", symbols, ...
    "Allocation", allocation, ...
    "Source", ...
        "nrPDCCHConfig.CORESET+SearchSpace monitoring occasion", ...
    "Exact", true);
end

function [startRB, numRB] = localCoordinatePRBEnvelope(coordinates)
if isempty(coordinates)
    error("sixgr:phy:frame:EmptyToolboxAllocation", ...
        "Toolbox channel functions returned no occupied carrier-grid RE.");
end
startRB = floor(min(coordinates(:, 1)) / 12);
lastRB = floor(max(coordinates(:, 1)) / 12);
numRB = lastRB - startRB + 1;
end

function [indices, domain] = localPDSCHReservedIndices(carrier, pdsch, dataInfo)
% R2026a nrPDSCHIndices/nrPDSCHPTRSIndices interpret ReservedRE on the
% BWP grid, collapse reservations across layers, and apply that union to
% every data layer. Do not decode these input indices using carrier stride.
% Native functions above remain the authority for actual mapped occupancy.
nStartBWP = pdsch.NStartBWP;
if isempty(nStartBWP), nStartBWP = carrier.NStartGrid; end
nSizeBWP = pdsch.NSizeBWP;
if isempty(nSizeBWP), nSizeBWP = carrier.NSizeGrid; end
bwpOffset = double(nStartBWP) - double(carrier.NStartGrid);
bwpK = 12 * double(nSizeBWP);
carrierK = 12 * double(carrier.NSizeGrid);
nSymbols = localSymbolsPerSlot(carrier);
nLayers = double(pdsch.NumLayers);
domain = struct("NStartBWP", double(nStartBWP), ...
    "NSizeBWP", double(nSizeBWP), "CarrierRBOffset", bwpOffset, ...
    "BWPSubcarrierCount", bwpK, "CarrierSubcarrierCount", carrierK, ...
    "SymbolsPerSlot", nSymbols, "NumLayers", nLayers, ...
    "LayerProjection", "union_across_input_layers_applied_to_all_data_layers", ...
    "MaterializedScope", "scheduled_native_prb_and_symbol_intersection");
indices = zeros(0, 1);
if isempty(pdsch.ReservedRE), return; end
% mod by one BWP page is exactly the native full-grid modulo followed by
% its layer union. Keep the original input shape/values in RateMatchProof.
oneLayer = unique(mod(double(pdsch.ReservedRE(:)), bwpK*nSymbols), "stable");
subcarrier = mod(oneLayer, bwpK);
symbol = floor(oneLayer / bwpK);
symbolAllocation = localSymbolAllocation(pdsch);
% A BWP reservation may lie outside this channel's allocation. It must not
% enlarge the PDSCH or become falsely published as one of its punctures.
% dataInfo.PRBSet is native PHYSICAL PRBs, including VRB interleaving.
inside = ismember(floor(subcarrier/12), double(dataInfo.PRBSet)) & ...
    symbol >= symbolAllocation(1) & ...
    symbol < sum(symbolAllocation);
if ~any(inside), return; end
carrierOneLayer = subcarrier(inside) + 12*bwpOffset + ...
    carrierK*symbol(inside) + 1;
indices = reshape(carrierOneLayer(:) + carrierK*nSymbols*(0:nLayers-1), [], 1);
end

function allocation = localSymbolAllocation(configObject)
allocation = double(localObjectValue( ...
    configObject, "SymbolAllocation", []));
allocation = allocation(:).';
if numel(allocation) ~= 2 || any(~isfinite(allocation)) || ...
        allocation(1) < 0 || allocation(2) <= 0 || ...
        any(allocation ~= fix(allocation))
    error("sixgr:phy:frame:InvalidToolboxSymbolAllocation", ...
        "Toolbox channel SymbolAllocation must be [start length].");
end
end

function keys = localKeys(coordinates, opt)
keys = strings(size(coordinates, 1), 1);
for index = 1:size(coordinates, 1)
    keys(index) = sprintf("%s|slot=%d|sc=%d|sym=%d|port=%d", ...
        opt.GridID, opt.AbsoluteSlot, coordinates(index, 1), ...
        coordinates(index, 2), coordinates(index, 3));
end
end

function reason = localReservedReason(keys, value)
if isempty(keys)
    reason = "";
else
    reason = string(value);
end
end

function count = localSymbolsPerSlot(carrier)
numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
    double(carrier.SubcarrierSpacing), string(carrier.CyclicPrefix), ...
    "generic_waveform_test", "");
count = double(numerology.SymbolsPerSlot);
end

function slot = localCarrierSlot(carrier)
slot = double(localObjectValue(carrier, "NSlot", 0));
end

function value = localObjectValue(object, name, fallback)
value = fallback;
try
    if isprop(object, name)
        value = object.(name);
    end
catch
end
end

function localRequireObject(value, className, label)
if ~isa(value, className)
    error("sixgr:phy:frame:InvalidToolboxAllocationObject", ...
        "%s must be a %s object.", label, className);
end
end

function tf = localNonnegativeInteger(value)
tf = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(double(value)) && double(value) >= 0 && ...
    double(value) == fix(double(value));
end
