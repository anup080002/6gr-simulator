function decision = resolveSRSPUCCHCollision( ...
        cfg, pucchGrant, absoluteSlotOneBased, srsUEIndex)
%RESOLVESRSPUCCHCOLLISION Exact shared-carrier SRS/PUCCH RE decision.
%
% FDD/TDD decides whether this UL occasion exists.  Once it exists, SRS
% and PUCCH occupy the same physical UL carrier and their exact Toolbox RE
% coordinates determine whether both transmissions can execute.

arguments
    cfg (1,1) struct
    pucchGrant
    absoluteSlotOneBased (1,1) double {mustBeFinite,mustBeInteger,mustBePositive}
    srsUEIndex (1,1) double {mustBeFinite,mustBeInteger,mustBePositive}
end
if istable(pucchGrant)
    if height(pucchGrant) ~= 1
        error("sixgr:phy:frame:InvalidPUCCHGrantRow", ...
            "Exact SRS/PUCCH resolution requires one PUCCH grant row.");
    end
    pucchGrant = table2struct(pucchGrant, "ToScalar", true);
end
if ~isstruct(pucchGrant) || ~isscalar(pucchGrant)
    error("sixgr:phy:frame:InvalidPUCCHGrantRow", ...
        "Exact SRS/PUCCH resolution requires a scalar grant structure.");
end

duplexMode = sixgr.phy.frame.resolveDuplexMode(cfg);
slot0 = absoluteSlotOneBased - 1;
[carrierProbe, ~] = sixgr.phy.grid.makeCarrier(cfg);
slotsPerFrame = localSlotsPerFrame(carrierProbe);
slotWithinFrame0 = mod(slot0, slotsPerFrame);
frame0 = floor(slot0 / slotsPerFrame);
[carrier, ~] = sixgr.phy.grid.makeCarrier(cfg, ...
    "Slot", slotWithinFrame0, "Frame", frame0);

strictSRS = sixgr.phy.srs.buildSRSConfigFromScenario(cfg);
srsAllocation = sixgr.phy.frame.ChannelAllocationMaterializer. ...
    materializeReferenceSignal(carrier, "SRS", strictSRS.ToolboxSRS, ...
    "AbsoluteSlot", slot0);

resourceId = string(localRequired(pucchGrant, "PUCCHResourceId"));
rnti = double(localRequired(pucchGrant, "RNTI"));
resourceData = localConfiguredResource(cfg, resourceId, rnti);
pucchResource = sixgr.phy.pucch.PUCCHResource(resourceData);
pucchAllocation = sixgr.phy.frame.ChannelAllocationMaterializer. ...
    materializePUCCH(carrier, pucchResource.toolboxConfig(), ...
    "AbsoluteSlot", slot0);

srsCoordinates = localTimeFrequencyCoordinates( ...
    srsAllocation.ActualCoordinates0Based);
pucchCoordinates = localTimeFrequencyCoordinates( ...
    pucchAllocation.ActualCoordinates0Based);
overlapCoordinates = intersect(srsCoordinates, pucchCoordinates, ...
    "rows", "stable");
collision = ~isempty(overlapCoordinates);
if collision
    action = "defer_srs_preserve_scheduled_pucch";
    status = "COLLISION_RESOLVED";
else
    action = "execute_srs";
    status = "NO_COLLISION";
end

decision = struct( ...
    "ContractVersion", "sixgr_srs_pucch_exact_re_collision/v1", ...
    "CollisionPair", "SRS_PUCCH", ...
    "DuplexMode", string(duplexMode), ...
    "AbsoluteSlotOneBased", double(absoluteSlotOneBased), ...
    "AbsoluteSlotZeroBased", double(slot0), ...
    "SlotWithinFrameZeroBased", double(slotWithinFrame0), ...
    "FrameZeroBased", double(frame0), ...
    "SRSUEIndex", double(srsUEIndex), ...
    "PUCCHUEIndex", double(localOptional(pucchGrant, "UEIndex", NaN)), ...
    "UEIndex", double(localOptional(pucchGrant, "UEIndex", NaN)), ...
    "PUCCHResourceId", resourceId, ...
    "SRSRECount", double(size(srsCoordinates, 1)), ...
    "PUCCHRECount", double(size(pucchCoordinates, 1)), ...
    "OverlapRECount", double(size(overlapCoordinates, 1)), ...
    "Collision", logical(collision), ...
    "Action", string(action), ...
    "Status", string(status), ...
    "SRSAllocationSource", string(srsAllocation.ToolboxSource), ...
    "PUCCHAllocationSource", string(pucchAllocation.ToolboxSource), ...
    "ResourceComparisonDomain", ...
        "shared_ul_carrier_subcarrier_symbol", ...
    "Exact", true, ...
    "ApproximationUsed", false, ...
    "OverlapCoordinates0Based", overlapCoordinates);
end

function data = localConfiguredResource(cfg, resourceId, rnti)
section = sixgr.util.structGet(cfg, "validation.pucch_resources", struct());
resources = sixgr.util.structGet(section, "resources", struct([]));
if ~(isstruct(resources) && ~isempty(resources))
    error("sixgr:phy:frame:MissingConfiguredPUCCHResources", ...
        "Exact SRS/PUCCH resolution requires configured PUCCH resources.");
end
match = false(numel(resources), 1);
for index = 1:numel(resources)
    match(index) = string(localOptional(resources(index), "id", "")) == resourceId;
end
indices = find(match);
if numel(indices) ~= 1
    error("sixgr:phy:frame:InvalidConfiguredPUCCHResourceIdentity", ...
        "PUCCH resource '%s' resolved to %d configured rows.", ...
        char(resourceId), numel(indices));
end
input = resources(indices);
data = struct( ...
    "ID", localRequiredNumber(input, ["id","resource_id"]), ...
    "Format", localRequiredNumber(input, "format"), ...
    "StartPRB", localRequiredNumber(input, "starting_prb"), ...
    "NumPRBs", localRequiredNumber(input, ["nrof_prbs","num_prb"]), ...
    "StartSymbol", localRequiredNumber(input, ["starting_symbol","symbol_start"]), ...
    "NumSymbols", localRequiredNumber(input, ["nrof_symbols","num_symbols"]), ...
    "IntraSlotHopping", logical(localRequired(input, ...
        ["intra_slot_hopping","intra_slot_frequency_hopping"])), ...
    "SecondHopStartPRB", localOptionalNumber(input, ...
        ["second_hop_start_prb","second_hop_prb"], NaN), ...
    "InitialCyclicShift", localRequiredNumber(input, "initial_cyclic_shift"), ...
    "OCCLength", localRequiredNumber(input, "occ_length"), ...
    "OCCIndex", localRequiredNumber(input, "occ_index"), ...
    "AdditionalDMRS", logical(localRequired(input, "additional_dmrs")), ...
    "Pi2BPSK", logical(localRequired(input, "pi2_bpsk")), ...
    "RNTI", double(rnti), ...
    "NID", localRequiredNumber(input, "nid"), ...
    "HoppingID", localRequiredNumber(input, "hopping_id"));
end

function value = localRequired(input, names)
value = [];
for name = string(names)
    if isstruct(input) && isfield(input, char(name)) && ...
            ~isempty(input.(char(name)))
        value = input.(char(name));
        return;
    end
end
error("sixgr:phy:frame:MissingExactPUCCHField", ...
    "Exact SRS/PUCCH resolution requires %s.", join(string(names), " or "));
end

function value = localOptional(input, name, fallback)
value = fallback;
if isstruct(input) && isfield(input, char(name)) && ...
        ~isempty(input.(char(name)))
    value = input.(char(name));
end
end

function value = localRequiredNumber(input, names)
value = double(localRequired(input, names));
if ~(isscalar(value) && isfinite(value))
    error("sixgr:phy:frame:InvalidExactPUCCHField", ...
        "Exact PUCCH field %s must be finite scalar.", join(string(names), "/"));
end
end

function value = localOptionalNumber(input, names, fallback)
value = fallback;
for name = string(names)
    if isfield(input, char(name)) && ~isempty(input.(char(name)))
        candidate = double(input.(char(name)));
        if isscalar(candidate) && isfinite(candidate)
            value = candidate;
        end
        return;
    end
end
end

function coordinates = localTimeFrequencyCoordinates(raw)
raw = double(raw);
if isempty(raw)
    coordinates = zeros(0, 2);
    return;
end
if size(raw, 2) < 2 || any(~isfinite(raw(:, 1:2)), "all")
    error("sixgr:phy:frame:InvalidExactRECoordinates", ...
        "Exact RE coordinates require finite subcarrier/symbol columns.");
end
coordinates = unique(raw(:, 1:2), "rows", "stable");
end

function value = localSlotsPerFrame(carrier)
mu = log2(double(carrier.SubcarrierSpacing) / 15);
if ~(isfinite(mu) && abs(mu - round(mu)) < 1e-9 && mu >= 0)
    error("sixgr:phy:frame:InvalidCarrierNumerology", ...
        "Carrier SCS does not resolve an NR numerology.");
end
value = 10 * 2^round(mu);
end
