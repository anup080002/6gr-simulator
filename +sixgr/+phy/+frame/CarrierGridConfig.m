classdef CarrierGridConfig
%CARRIERGRIDCONFIG Validated standard or explicit custom carrier-grid state.
%
% Standard NR construction delegates to TransmissionBandwidthCatalog.
% Research grids require the separate custom API and are always labeled
% non-standard.

    methods (Static)
        function result = resolve(varargin)
        %RESOLVE Build a validated standard NR carrier-grid snapshot.
            [catalogArgs, nStartBWP, nSizeBWP, bwpSCSKHz, cyclicPrefix] = ...
                localSplitBWPArgs(varargin{:});
            result = sixgr.phy.frame.TransmissionBandwidthCatalog.resolve(catalogArgs{:});
            numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
                result.SubcarrierSpacingKHz, cyclicPrefix, ...
                "carrier_transmission_grid", result.FrequencyRange);
            result.Kind = "standard_nr_carrier_grid";
            result.CyclicPrefix = char(string(numerology.CyclicPrefix));
            result.Mu = double(numerology.Mu);
            result.SymbolsPerSlot = double(numerology.SymbolsPerSlot);
            result.SlotsPerSubframe = double(numerology.SlotsPerSubframe);
            result.SlotsPerFrame = double(numerology.SlotsPerFrame);
            result.SlotDurationSeconds = double(numerology.SlotDurationSeconds);
            result.Numerology = numerology;
            result.ActiveBWP = localResolveBWP( ...
                result.NStartGrid, result.NSizeGrid, ...
                result.SubcarrierSpacingKHz, nStartBWP, nSizeBWP, ...
                bwpSCSKHz);
            result.IndexConvention = "zero_based_phy_indices";
        end

        function result = custom(varargin)
        %CUSTOM Build an explicitly labeled non-standard research grid.
            opts = localCustomInputs(varargin{:});
            if ~logical(opts.ResearchMode)
                error("sixgr:phy:frame:CustomCarrierRequiresOptIn", ...
                    "Custom carrier grids require ResearchMode=true.");
            end
            nSizeGrid = localPositiveInteger(opts.NSizeGrid, "NSizeGrid");
            nStartGrid = localNonnegativeInteger(opts.NStartGrid, "NStartGrid");
            scsKHz = localPositiveScalar(opts.SubcarrierSpacingKHz, ...
                "SubcarrierSpacingKHz");
            centerHz = localPositiveScalar(opts.CenterFrequencyHz, ...
                "CenterFrequencyHz");
            bandwidthMHz = localPositiveScalar(opts.ChannelBandwidthMHz, ...
                "ChannelBandwidthMHz");
            occupiedBandwidthHz = 12 * nSizeGrid * scsKHz * 1e3;
            if occupiedBandwidthHz > bandwidthMHz * 1e6
                error("sixgr:phy:frame:CustomGridExceedsBandwidth", ...
                    "Custom occupied bandwidth %.15g Hz exceeds channel bandwidth %.15g Hz.", ...
                    occupiedBandwidthHz, bandwidthMHz * 1e6);
            end
            % A custom research grid is deliberately outside the pinned NR
            % numerology catalog.  Do not coerce its SCS to the nearest NR
            % mu or label its timing as TS 38.211.  Instead, retain the
            % configured SCS exactly and derive the explicit 15-kHz-relative
            % research timing used by this grid.
            numerology = localResearchNumerology(scsKHz, opts.CyclicPrefix);
            lowGuardHz = localOptionalNonnegativeScalar( ...
                opts.MinimumLowGuardbandHz, "MinimumLowGuardbandHz");
            highGuardHz = localOptionalNonnegativeScalar( ...
                opts.MinimumHighGuardbandHz, "MinimumHighGuardbandHz");
            if isfinite(lowGuardHz) && isfinite(highGuardHz) && ...
                    occupiedBandwidthHz + lowGuardHz + highGuardHz > bandwidthMHz * 1e6
                error("sixgr:phy:frame:CustomGridGuardbandExceedsBandwidth", ...
                    "Occupied bandwidth plus explicit low/high guardbands exceeds the custom channel bandwidth.");
            end
            result = struct( ...
                "Valid", true, ...
                "StandardNR", false, ...
                "Kind", "explicit_custom_research_grid", ...
                "ResearchClass", "optional_research_experiment", ...
                "Role", "custom_research_carrier", ...
                "FrequencyRange", "CUSTOM", ...
                "FrequencyRangeSubtype", "CUSTOM", ...
                "CenterFrequencyHz", double(centerHz), ...
                "ChannelBandwidthMHz", double(bandwidthMHz), ...
                "ChannelBandwidthHz", double(bandwidthMHz * 1e6), ...
                "SubcarrierSpacingKHz", double(scsKHz), ...
                "N_RB", double(nSizeGrid), ...
                "NSizeGrid", double(nSizeGrid), ...
                "NStartGrid", double(nStartGrid), ...
                "OccupiedSubcarrierCount", double(12 * nSizeGrid), ...
                "OccupiedBandwidthHz", double(occupiedBandwidthHz), ...
                "MinimumLowGuardbandHz", lowGuardHz, ...
                "MinimumHighGuardbandHz", highGuardHz, ...
                "SourceTable", "none_custom_research_grid", ...
                "Source", "explicit_custom_research_configuration", ...
                "IndexConvention", "zero_based_phy_indices");
            result.CyclicPrefix = char(string(numerology.CyclicPrefix));
            result.Mu = double(numerology.Mu);
            result.SymbolsPerSlot = double(numerology.SymbolsPerSlot);
            result.SlotsPerSubframe = double(numerology.SlotsPerSubframe);
            result.SlotsPerFrame = double(numerology.SlotsPerFrame);
            result.SlotDurationSeconds = double(numerology.SlotDurationSeconds);
            result.Numerology = numerology;
            result.ActiveBWP = localResolveBWP( ...
                nStartGrid, nSizeGrid, scsKHz, ...
                opts.NStartBWP, opts.NSizeBWP, ...
                opts.BWPSubcarrierSpacingKHz);
        end
    end
end

function result = localResearchNumerology(scsKHz, cyclicPrefix)
cyclicPrefix = lower(strtrim(string(cyclicPrefix)));
if ~any(cyclicPrefix == ["normal", "extended"])
    error("sixgr:phy:frame:InvalidCyclicPrefix", ...
        "CyclicPrefix must be the scalar text value 'normal' or 'extended'.");
end
symbolsPerSlot = 14;
if cyclicPrefix == "extended"
    symbolsPerSlot = 12;
end
slotRatePerMillisecond = double(scsKHz) / 15;
result = struct( ...
    "Mu", log2(slotRatePerMillisecond), ...
    "SubcarrierSpacingKHz", double(scsKHz), ...
    "CyclicPrefix", char(cyclicPrefix), ...
    "SymbolsPerSlot", double(symbolsPerSlot), ...
    "SlotsPerSubframe", double(slotRatePerMillisecond), ...
    "SlotsPerFrame", double(10 * slotRatePerMillisecond), ...
    "SlotDurationSeconds", double(1e-3 / slotRatePerMillisecond), ...
    "SlotDurationMilliseconds", double(1 / slotRatePerMillisecond), ...
    "Role", "custom_research_carrier", ...
    "FrequencyRange", "CUSTOM", ...
    "StandardNR", false, ...
    "IndexConvention", "zero_based_phy_indices", ...
    "Source", "explicit_nonstandard_15kHz_relative_research_timing");
end

function [catalogArgs, nStartBWP, nSizeBWP, bwpSCSKHz, cyclicPrefix] = ...
        localSplitBWPArgs(varargin)
catalogArgs = {};
nStartBWP = [];
nSizeBWP = [];
bwpSCSKHz = [];
cyclicPrefix = "normal";
if mod(numel(varargin), 2) ~= 0
    error("sixgr:phy:frame:InvalidCarrierGridArguments", ...
        "CarrierGridConfig arguments must occur in name-value pairs.");
end
for i = 1:2:numel(varargin)
    name = lower(strtrim(string(varargin{i})));
    value = varargin{i + 1};
    if name == "nstartbwp"
        nStartBWP = value;
    elseif name == "nsizebwp"
        nSizeBWP = value;
    elseif any(name == ["bwpsubcarrierspacingkhz", "bwpscskhz"])
        bwpSCSKHz = value;
    elseif name == "cyclicprefix"
        cyclicPrefix = value;
    else
        catalogArgs = [catalogArgs, varargin(i:i + 1)]; %#ok<AGROW>
    end
end
end

function bwp = localResolveBWP(nStartGrid, nSizeGrid, carrierSCSKHz, ...
        nStartBWP, nSizeBWP, bwpSCSKHz)
if isempty(nStartBWP) && isempty(nSizeBWP)
    bwp = struct( ...
        "Configured", false, ...
        "NStartBWP", NaN, ...
        "NSizeBWP", NaN, ...
        "SubcarrierSpacingKHz", NaN, ...
        "LowerEdgeOffsetHz", NaN, ...
        "UpperEdgeOffsetHz", NaN, ...
        "IndexConvention", "zero_based_phy_indices");
    return;
end
if isempty(nStartBWP) || isempty(nSizeBWP)
    error("sixgr:phy:frame:IncompleteBWPGrid", ...
        "NStartBWP and NSizeBWP must be configured together.");
end
nStartBWP = localNonnegativeInteger(nStartBWP, "NStartBWP");
nSizeBWP = localPositiveInteger(nSizeBWP, "NSizeBWP");
carrierSCSKHz = localPositiveScalar(carrierSCSKHz, ...
    "SubcarrierSpacingKHz");
if isempty(bwpSCSKHz)
    bwpSCSKHz = carrierSCSKHz;
else
    bwpSCSKHz = localPositiveScalar(bwpSCSKHz, ...
        "BWPSubcarrierSpacingKHz");
end
quantumHz = 12 * 1e3 * ...
    gcd(round(carrierSCSKHz), round(bwpSCSKHz));
carrierLowerHz = 12 * 1e3 * nStartGrid * carrierSCSKHz;
carrierUpperHz = 12 * 1e3 * ...
    (nStartGrid + nSizeGrid) * carrierSCSKHz;
bwpLowerHz = 12 * 1e3 * nStartBWP * bwpSCSKHz;
bwpUpperHz = 12 * 1e3 * ...
    (nStartBWP + nSizeBWP) * bwpSCSKHz;
edgeTicks = [carrierLowerHz, carrierUpperHz, ...
    bwpLowerHz, bwpUpperHz] / quantumHz;
if any(abs(edgeTicks - round(edgeTicks)) > 1e-9)
    error("sixgr:phy:frame:BWPPointAAlignmentMismatch", ...
        "BWP and carrier edges do not align on their common Point-A frequency raster.");
end
if bwpLowerHz < carrierLowerHz || bwpUpperHz > carrierUpperHz
    error("sixgr:phy:frame:BWPOutsideCarrierGrid", ...
        "BWP Point-A offsets [%.15g,%.15g) Hz at %.15g kHz SCS " + ...
        "lie outside carrier offsets [%.15g,%.15g) Hz at %.15g kHz SCS.", ...
        bwpLowerHz, bwpUpperHz, bwpSCSKHz, ...
        carrierLowerHz, carrierUpperHz, carrierSCSKHz);
end
bwp = struct( ...
    "Configured", true, ...
    "NStartBWP", double(nStartBWP), ...
    "NSizeBWP", double(nSizeBWP), ...
    "SubcarrierSpacingKHz", double(bwpSCSKHz), ...
    "LowerEdgeOffsetHz", double(bwpLowerHz), ...
    "UpperEdgeOffsetHz", double(bwpUpperHz), ...
    "CarrierLowerEdgeOffsetHz", double(carrierLowerHz), ...
    "CarrierUpperEdgeOffsetHz", double(carrierUpperHz), ...
    "PointAAlignmentQuantumHz", double(quantumHz), ...
    "IndexConvention", "zero_based_phy_indices");
end

function opts = localCustomInputs(varargin)
opts = struct( ...
    "ResearchMode", false, ...
    "CenterFrequencyHz", [], ...
    "ChannelBandwidthMHz", [], ...
    "SubcarrierSpacingKHz", [], ...
    "NSizeGrid", [], ...
    "NStartGrid", 0, ...
    "CyclicPrefix", "normal", ...
    "MinimumLowGuardbandHz", [], ...
    "MinimumHighGuardbandHz", [], ...
    "NStartBWP", [], ...
    "NSizeBWP", [], ...
    "BWPSubcarrierSpacingKHz", []);
if mod(numel(varargin), 2) ~= 0
    error("sixgr:phy:frame:InvalidCarrierGridArguments", ...
        "Custom carrier arguments must occur in name-value pairs.");
end
names = fieldnames(opts);
for i = 1:2:numel(varargin)
    supplied = string(varargin{i});
    index = find(strcmpi(supplied, names), 1);
    if isempty(index)
        error("sixgr:phy:frame:InvalidCarrierGridArguments", ...
            "Unknown custom carrier option '%s'.", char(supplied));
    end
    opts.(names{index}) = varargin{i + 1};
end
end

function value = localOptionalNonnegativeScalar(raw, fieldName)
if isempty(raw)
    value = NaN;
    return;
end
if ~(isnumeric(raw) || islogical(raw)) || ~isscalar(raw) || ...
        ~isfinite(double(raw)) || double(raw) < 0
    error("sixgr:phy:frame:InvalidCarrierGridValue", ...
        "%s must be a nonnegative finite numeric scalar when supplied.", fieldName);
end
value = double(raw);
end

function value = localPositiveScalar(raw, fieldName)
if ~(isnumeric(raw) || islogical(raw)) || ~isscalar(raw) || ...
        ~isfinite(double(raw)) || double(raw) <= 0
    error("sixgr:phy:frame:InvalidCarrierGridValue", ...
        "%s must be a positive finite numeric scalar.", fieldName);
end
value = double(raw);
end

function value = localPositiveInteger(raw, fieldName)
value = localPositiveScalar(raw, fieldName);
if value ~= round(value)
    error("sixgr:phy:frame:InvalidCarrierGridValue", ...
        "%s must be a positive integer.", fieldName);
end
value = round(value);
end

function value = localNonnegativeInteger(raw, fieldName)
if isempty(raw)
    raw = 0;
end
if ~(isnumeric(raw) || islogical(raw)) || ~isscalar(raw) || ...
        ~isfinite(double(raw)) || double(raw) < 0 || double(raw) ~= round(double(raw))
    error("sixgr:phy:frame:InvalidCarrierGridValue", ...
        "%s must be a nonnegative integer.", fieldName);
end
value = round(double(raw));
end
