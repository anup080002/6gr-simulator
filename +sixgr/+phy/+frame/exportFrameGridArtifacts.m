function manifest = exportFrameGridArtifacts(outputDirectory, varargin)
%EXPORTFRAMEGRIDARTIFACTS Export deterministic frame/grid conformance evidence.
%
% Every primary CSV is built by invoking the canonical production frame
% resolvers. Golden CSVs are comparison inputs in the tests; they are never
% copied into this output directory. PHY-facing indices in these artifacts
% are zero based.

parser = inputParser;
parser.FunctionName = "sixgr.phy.frame.exportFrameGridArtifacts";
addRequired(parser, "outputDirectory", @localTextScalar);
addParameter(parser, "TestSummary", table(), @istable);
addParameter(parser, "RequireAllPass", true, ...
    @(v) islogical(v) && isscalar(v));
parse(parser, outputDirectory, varargin{:});

outputDirectory = char(string(parser.Results.outputDirectory));
if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end
vectorDirectory = localVectorDirectory();

tables = struct();
tables.frame_numerology_matrix = localNumerologyMatrix(vectorDirectory);
tables.carrier_grid_matrix = localCarrierGridMatrix(vectorDirectory);
tables.slot_symbol_ownership = localSlotSymbolOwnership(vectorDirectory);
[tables.allocation_legality, tables.resource_grid_occupancy] = ...
    localAllocationArtifacts(vectorDirectory);
tables.ofdm_roundtrip = localOFDMRoundtrip(vectorDirectory);
[tables.timing_matrix, tables.bwp_switch_trace, ...
    tables.component_carrier_trace] = localTimingArtifacts();
tables.ssb_timing_matrix = localSSBTimingMatrix();
tables.prach_occasion_matrix = localPRACHOccasionMatrix();
tables.fdd_grid_trace = localFDDGridTrace();
tables.shortcut_removal_audit = localShortcutRemovalAudit();

summary = parser.Results.TestSummary;
if isempty(summary)
    error("sixgr:phy:frame:MissingFrameGridTestSummary", ...
        "A nonempty table of actually executed MATLAB tests is required.");
end
tables.frame_fix_test_summary = localNormalizeTestSummary(summary);

csvOrder = [ ...
    "frame_numerology_matrix"
    "carrier_grid_matrix"
    "slot_symbol_ownership"
    "resource_grid_occupancy"
    "allocation_legality"
    "ofdm_roundtrip"
    "timing_matrix"
    "bwp_switch_trace"
    "component_carrier_trace"
    "ssb_timing_matrix"
    "prach_occasion_matrix"
    "fdd_grid_trace"
    "shortcut_removal_audit"
    "frame_fix_test_summary"];
for name = csvOrder.'
    tables.(name) = localWithIndexConvention(tables.(name));
    writetable(tables.(name), fullfile(outputDirectory, name + ".csv"));
end

audit = localExportImages(outputDirectory, tables);
audit = localWithIndexConvention(audit);
writetable(audit, fullfile(outputDirectory, "frame_image_audit.csv"));
tables.frame_image_audit = audit;

csvFiles = [csvOrder + ".csv"; "frame_image_audit.csv"];
imageFiles = string(audit.ImageFile);
manifest = struct( ...
    "OutputDirectory", string(outputDirectory), ...
    "CSVFiles", csvFiles, ...
    "ImageFiles", imageFiles, ...
    "CSVCount", numel(csvFiles), ...
    "ImageCount", numel(imageFiles), ...
    "AllStatusPass", localAllStatusPass(tables), ...
    "IndexConvention", "zero_based_phy_indices");

if manifest.CSVCount ~= 15 || manifest.ImageCount ~= 9
    error("sixgr:phy:frame:ArtifactCountMismatch", ...
        "Frame/grid export produced %d CSVs and %d PNGs; expected 15 and 9.", ...
        manifest.CSVCount, manifest.ImageCount);
end
if parser.Results.RequireAllPass && ~manifest.AllStatusPass
    error("sixgr:phy:frame:FrameGridArtifactFailure", ...
        "At least one generated frame/grid evidence row has Status other than PASS.");
end
end

function tableOut = localNumerologyMatrix(vectorDirectory)
vectors = readtable(fullfile(vectorDirectory, ...
    "frame_numerology_test_vectors.csv"), "TextType", "string");
n = height(vectors);
testID = string(vectors.TestID);
mu = double(vectors.Mu);
scs = double(vectors.SCS_kHz);
cp = string(vectors.CyclicPrefix);
expectedValid = strings(n, 1);
resolvedValid = repmat("FALSE", n, 1);
expectedSymbols = double(vectors.ExpectedSymbolsPerSlot);
resolvedSymbols = nan(n, 1);
expectedSlotsSubframe = double(vectors.ExpectedSlotsPerSubframe);
resolvedSlotsSubframe = nan(n, 1);
expectedSlotsFrame = double(vectors.ExpectedSlotsPerFrame);
resolvedSlotsFrame = nan(n, 1);
errorID = strings(n, 1);
status = repmat("FAIL", n, 1);

for index = 1:n
    expected = localTruth(vectors.ExpectedValid(index));
    expectedValid(index) = localBoolText(expected);
    try
        result = sixgr.phy.frame.NumerologyCatalog.resolve( ...
            scs(index), cp(index), "generic_waveform_test", "");
        resolvedValid(index) = "TRUE";
        resolvedSymbols(index) = result.SymbolsPerSlot;
        resolvedSlotsSubframe(index) = result.SlotsPerSubframe;
        resolvedSlotsFrame(index) = result.SlotsPerFrame;
        matches = expected && result.Mu == mu(index) && ...
            result.SubcarrierSpacingKHz == scs(index) && ...
            string(result.CyclicPrefix) == lower(cp(index)) && ...
            result.SymbolsPerSlot == expectedSymbols(index) && ...
            result.SlotsPerSubframe == expectedSlotsSubframe(index) && ...
            result.SlotsPerFrame == expectedSlotsFrame(index);
    catch cause
        errorID(index) = string(cause.identifier);
        matches = ~expected && errorID(index) == ...
            string(vectors.ExpectedErrorID(index));
    end
    status(index) = localPassText(matches);
end

tableOut = table(testID, mu, scs, cp, expectedValid, resolvedValid, ...
    expectedSymbols, resolvedSymbols, expectedSlotsSubframe, ...
    resolvedSlotsSubframe, expectedSlotsFrame, resolvedSlotsFrame, ...
    errorID, status, 'VariableNames', [ ...
    "TestID","Mu","SCS_kHz","CyclicPrefix","ExpectedValid", ...
    "ResolvedValid","ExpectedSymbolsPerSlot","ResolvedSymbolsPerSlot", ...
    "ExpectedSlotsPerSubframe","ResolvedSlotsPerSubframe", ...
    "ExpectedSlotsPerFrame","ResolvedSlotsPerFrame","ErrorID","Status"]);
end

function tableOut = localCarrierGridMatrix(vectorDirectory)
vectors = readtable(fullfile(vectorDirectory, ...
    "frame_carrier_grid_test_vectors.csv"), "TextType", "string");
n = height(vectors);
testID = string(vectors.TestID);
role = string(vectors.Role);
frequencyRange = string(vectors.FrequencyRange);
centerHz = double(vectors.RepresentativeCenterFrequency_Hz);
bandwidthMHz = double(vectors.ChannelBandwidth_MHz);
scsKHz = double(vectors.CarrierSCS_kHz);
expectedValid = strings(n, 1);
resolvedValid = repmat("FALSE", n, 1);
expectedNRB = double(vectors.ExpectedNRB);
resolvedNRB = nan(n, 1);
nStartGrid = nan(n, 1);
occupiedHz = nan(n, 1);
guardLowHz = nan(n, 1);
guardHighHz = nan(n, 1);
channelLowHz = nan(n, 1);
channelHighHz = nan(n, 1);
transmissionLowHz = nan(n, 1);
transmissionHighHz = nan(n, 1);
activeBWPStartRB = nan(n, 1);
activeBWPSizeRB = nan(n, 1);
activeBWPLowHz = nan(n, 1);
activeBWPHighHz = nan(n, 1);
errorID = strings(n, 1);
status = repmat("FAIL", n, 1);

for index = 1:n
    expected = localTruth(vectors.ExpectedValid(index));
    expectedValid(index) = localBoolText(expected);
    try
        result = sixgr.phy.frame.CarrierGridConfig.resolve( ...
            "Role", role(index), ...
            "FrequencyRange", frequencyRange(index), ...
            "CenterFrequencyHz", centerHz(index), ...
            "ChannelBandwidthMHz", bandwidthMHz(index), ...
            "SubcarrierSpacingKHz", scsKHz(index));
        resolvedValid(index) = "TRUE";
        resolvedNRB(index) = result.NSizeGrid;
        nStartGrid(index) = result.NStartGrid;
        occupiedHz(index) = result.OccupiedBandwidthHz;
        guardLowHz(index) = result.MinimumLowGuardbandHz;
        guardHighHz(index) = result.MinimumHighGuardbandHz;
        channelLowHz(index) = centerHz(index) - ...
            bandwidthMHz(index) * 1e6 / 2;
        channelHighHz(index) = centerHz(index) + ...
            bandwidthMHz(index) * 1e6 / 2;
        transmissionLowHz(index) = centerHz(index) - ...
            occupiedHz(index) / 2;
        transmissionHighHz(index) = centerHz(index) + ...
            occupiedHz(index) / 2;
        activeBWPSizeRB(index) = max(1, floor(result.NSizeGrid / 2));
        activeBWPStartRB(index) = result.NStartGrid + ...
            floor((result.NSizeGrid - activeBWPSizeRB(index)) / 2);
        activeBWPLowHz(index) = transmissionLowHz(index) + ...
            (activeBWPStartRB(index) - result.NStartGrid) * ...
            12 * scsKHz(index) * 1e3;
        activeBWPHighHz(index) = activeBWPLowHz(index) + ...
            activeBWPSizeRB(index) * 12 * scsKHz(index) * 1e3;
        expectedGuardHz = double(vectors.ExpectedMinGuardband_kHz(index)) * 1e3;
        matches = expected && result.NSizeGrid == expectedNRB(index) && ...
            result.NStartGrid == 0 && ...
            abs(guardLowHz(index) - expectedGuardHz) < 1e-9 && ...
            abs(guardHighHz(index) - expectedGuardHz) < 1e-9;
    catch cause
        errorID(index) = string(cause.identifier);
        matches = ~expected && errorID(index) == ...
            string(vectors.ExpectedErrorID(index));
    end
    status(index) = localPassText(matches);
end

tableOut = table(testID, role, frequencyRange, centerHz, bandwidthMHz, ...
    scsKHz, expectedValid, resolvedValid, expectedNRB, resolvedNRB, ...
    nStartGrid, occupiedHz, guardLowHz, guardHighHz, ...
    channelLowHz, channelHighHz, transmissionLowHz, transmissionHighHz, ...
    activeBWPStartRB, activeBWPSizeRB, activeBWPLowHz, activeBWPHighHz, ...
    errorID, status, ...
    'VariableNames', [ ...
    "TestID","Role","FrequencyRange","CenterFrequency_Hz", ...
    "ChannelBandwidth_MHz","CarrierSCS_kHz","ExpectedValid", ...
    "ResolvedValid","ExpectedNRB","ResolvedNRB","NStartGrid", ...
    "OccupiedBandwidth_Hz","GuardbandLow_Hz","GuardbandHigh_Hz", ...
    "ChannelLowEdge_Hz","ChannelHighEdge_Hz", ...
    "TransmissionLowEdge_Hz","TransmissionHighEdge_Hz", ...
    "ActiveBWPStartRB","ActiveBWPSizeRB", ...
    "ActiveBWPLowEdge_Hz","ActiveBWPHighEdge_Hz", ...
    "ErrorID","Status"]);
end

function tableOut = localSlotSymbolOwnership(vectorDirectory)
vectors = readtable(fullfile(vectorDirectory, ...
    "frame_tdd_test_vectors.csv"), "TextType", "string");
parts = cell(0, 1);
for index = 1:height(vectors)
    row = vectors(index, :);
    if ~localTruth(row.ExpectedValid)
        continue;
    end
    common = localTDDCommon(row);
    if ismissing(row.DedicatedMode) || ...
            strlength(strtrim(row.DedicatedMode)) == 0
        state = common;
        dedicated = strings(size(common.CommonDirection));
    else
        rule = localDedicatedRule(row);
        state = sixgr.phy.frame.TDDDedicatedConfig.apply(common, rule);
        dedicated = state.DedicatedDirection;
    end
    commonDirection = common.CommonDirection;
    resolved = state.ResolvedDirection;
    [slots, symbols] = size(commonDirection);
    count = slots * symbols;
    testID = repmat(string(row.TestID), count, 1);
    cellID = zeros(count, 1);
    ccid = zeros(count, 1);
    bwpid = zeros(count, 1);
    frame = zeros(count, 1);
    slot = repelem((0:(slots - 1)).', symbols);
    slot = slot(:);
    symbol = repmat((0:(symbols - 1)).', slots, 1);
    commonText = string(reshape(commonDirection.', [], 1));
    dedicatedText = reshape(dedicated.', [], 1);
    resolvedText = reshape(resolved.', [], 1);
    source = repmat("common", count, 1);
    flex = commonText == "F";
    source(flex) = "unresolved_flexible";
    dedicatedConfigured = strlength(dedicatedText) > 0;
    source(dedicatedConfigured & dedicatedText ~= "F") = "dedicated";
    source(dedicatedConfigured & dedicatedText == "F") = ...
        "dedicated_flexible";
    owner = strings(count, 1);
    status = repmat("PASS", count, 1);
    localAssertRowCounts(string(row.TestID), count, ...
        testID, cellID, ccid, bwpid, frame, slot, symbol, commonText, ...
        dedicatedText, resolvedText, source, owner, status);
    parts{end + 1, 1} = table( ... %#ok<AGROW>
        testID, cellID, ccid, bwpid, frame, slot, symbol, ...
        commonText, dedicatedText, resolvedText, source, owner, status, ...
        'VariableNames', [ ...
        "TestID","CellID","CCID","BWPID","Frame","Slot","Symbol", ...
        "CommonDirection","DedicatedDirection","ResolvedDirection", ...
        "ResolutionSource","AllocationOwner","Status"]);
end
tableOut = vertcat(parts{:});
end

function common = localTDDCommon(row)
cp = "normal";
if string(row.TestID) == "TDD-011"
    cp = "extended";
end
p1 = localPattern(row.Pattern1Periodicity_ms, row.P1_DLSlots, ...
    row.P1_DLSymbols, row.P1_ULSlots, row.P1_ULSymbols);
p2 = struct();
if isfinite(row.Pattern2Periodicity_ms)
    p2 = localPattern(row.Pattern2Periodicity_ms, row.P2_DLSlots, ...
        row.P2_DLSymbols, row.P2_ULSlots, row.P2_ULSymbols);
end
common = sixgr.phy.frame.TDDCommonConfig.resolve( ...
    "ReferenceSubcarrierSpacingKHz", row.ReferenceSCS_kHz, ...
    "ActiveSubcarrierSpacingKHz", row.ActiveSCS_kHz, ...
    "CyclicPrefix", cp, "Pattern1", p1, "Pattern2", p2);
end

function pattern = localPattern(period, dlSlots, dlSymbols, ulSlots, ulSymbols)
pattern = struct( ...
    "PeriodicityMilliseconds", double(period), ...
    "NumDownlinkSlots", double(dlSlots), ...
    "NumDownlinkSymbols", double(dlSymbols), ...
    "NumUplinkSlots", double(ulSlots), ...
    "NumUplinkSymbols", double(ulSymbols));
end

function rule = localDedicatedRule(row)
rule = struct( ...
    "SlotIndex", double(row.DedicatedSlotIndex), ...
    "Mode", string(row.DedicatedMode));
if lower(string(row.DedicatedMode)) == "explicit"
    rule.FirstDownlinkSymbols = double(row.DedicatedDLSymbols);
    rule.LastUplinkSymbols = double(row.DedicatedULSymbols);
end
end

function [legality, occupancyOut] = localAllocationArtifacts(vectorDirectory)
vectors = readtable(fullfile(vectorDirectory, ...
    "frame_allocation_test_vectors.csv"), "TextType", "string");
n = height(vectors);
testID = string(vectors.TestID);
channel = string(vectors.Channel);
direction = string(vectors.Direction);
ccid = zeros(n, 1);
bwpid = zeros(n, 1);
absoluteSlot = zeros(n, 1);
startSymbol = double(vectors.StartSymbol);
numSymbols = double(vectors.NumSymbols);
startRB = zeros(n, 1);
numRB = ones(n, 1);
flexDecision = string(vectors.FlexResolution);
expectedValid = strings(n, 1);
actualValid = strings(n, 1);
reasonCode = strings(n, 1);
status = repmat("FAIL", n, 1);

for index = 1:n
    [state, conflict] = localAllocationState( ...
        vectors.SymbolMap(index), vectors.FlexResolution(index));
    if strlength(conflict) > 0
        valid = false;
        reason = conflict;
    else
        allocation = localVectorAllocation(vectors(index, :));
        result = sixgr.phy.frame.ResourceAllocationValidator.validate( ...
            allocation, state);
        valid = result.ActualValid;
        reason = result.ReasonCode;
    end
    expected = localTruth(vectors.ExpectedValid(index));
    expectedValid(index) = localBoolText(expected);
    actualValid(index) = localBoolText(valid);
    reasonCode(index) = reason;
    status(index) = localPassText(valid == expected && ...
        reason == string(vectors.ExpectedReasonCode(index)));
end
legality = table(testID, channel, direction, ccid, bwpid, ...
    absoluteSlot, startSymbol, numSymbols, startRB, numRB, ...
    flexDecision, expectedValid, actualValid, reasonCode, status, ...
    'VariableNames', [ ...
    "TestID","Channel","Direction","CCID","BWPID","AbsoluteSlot", ...
    "StartSymbol","NumSymbols","StartRB","NumRB","FlexDecision", ...
    "ExpectedValid","ActualValid","ReasonCode","Status"]);

p = struct("PeriodicityMilliseconds", 1, ...
    "NumDownlinkSlots", 1, "NumDownlinkSymbols", 0, ...
    "NumUplinkSlots", 0, "NumUplinkSymbols", 0);
slotState = sixgr.phy.frame.TDDCommonConfig.resolve( ...
    "ReferenceSubcarrierSpacingKHz", 15, ...
    "ActiveSubcarrierSpacingKHz", 15, "Pattern1", p);
allocations(1) = sixgr.phy.frame.ResourceAllocationValidator.makeAllocation( ...
    "PDCCH", "DL", "CCID", 0, "BWPID", 0, "AbsoluteSlot", 0, ...
    "StartSymbol", 0, "NumSymbols", 2, "StartRB", 0, "NumRB", 4, ...
    "GridNumRB", 24, "Ports", 0, "TestID", "OCC-PDCCH", ...
    "GridID", "cc0_bwp0_dl_grid");
controlResult = sixgr.phy.frame.ResourceAllocationValidator.validate( ...
    allocations(1), slotState, "GridNumRB", 24);
if ~controlResult.ActualValid
    error("sixgr:phy:frame:OccupancyControlAllocationInvalid", ...
        "Canonical CORESET occupancy failed: %s", ...
        controlResult.ReasonCode);
end
reservedKeys = controlResult.Occupancy.REKey;
allocations(2) = sixgr.phy.frame.ResourceAllocationValidator.makeAllocation( ...
    "PDSCH", "DL", "CCID", 0, "BWPID", 0, "AbsoluteSlot", 0, ...
    "StartSymbol", 0, "NumSymbols", 14, "MappingType", "A", ...
    "StartRB", 0, "NumRB", 24, "GridNumRB", 24, "Ports", 0, ...
    "RateMatchedREKeys", reservedKeys, ...
    "ReservedREKeys", reservedKeys, ...
    "ReservedReason", "coreset_re_reservation", ...
    "TestID", "OCC-PDSCH", "GridID", "cc0_bwp0_dl_grid");
report = sixgr.phy.frame.ResourceAllocationValidator.validateSet( ...
    allocations, slotState, "GridNumRB", 24);
if ~report.ActualValid
    error("sixgr:phy:frame:OccupancyScenarioInvalid", ...
        "Canonical occupancy scenario failed: %s", report.ReasonCode);
end
raw = report.Occupancy;
reservationAudit = controlResult.Occupancy;
reservationAudit.TestID(:) = "OCC-PDSCH-RATE-MATCHED";
reservationAudit.Channel(:) = "PDSCH_EXCLUDED";
reservationAudit.CollisionFlag(:) = true;
reservationAudit.ReservedReason(:) = "coreset_re_reservation";
raw = [raw; reservationAudit];
groups = findgroups( ...
    raw.TestID, raw.CCID, raw.BWPID, raw.Slot, raw.Symbol, raw.RB, ...
    raw.Port, raw.Channel, raw.Direction);
rowCount = max(groups);
collision = splitapply(@any, raw.CollisionFlag, groups);
reserved = splitapply(@(x) strjoin(unique(x), ";"), raw.ReservedReason, groups);
testValue = splitapply(@(x) x(1), raw.TestID, groups);
ccValue = splitapply(@(x) x(1), raw.CCID, groups);
bwpValue = splitapply(@(x) x(1), raw.BWPID, groups);
slotValue = splitapply(@(x) x(1), raw.Slot, groups);
symbolValue = splitapply(@(x) x(1), raw.Symbol, groups);
rbValue = splitapply(@(x) x(1), raw.RB, groups);
portValue = splitapply(@(x) x(1), raw.Port, groups);
channelValue = splitapply(@(x) x(1), raw.Channel, groups);
directionValue = splitapply(@(x) x(1), raw.Direction, groups);
statusValue = repmat("PASS", rowCount, 1);
occupancyOut = table(testValue, ccValue, bwpValue, slotValue, ...
    symbolValue, rbValue, portValue, channelValue, directionValue, ...
    collision, reserved, statusValue, 'VariableNames', [ ...
    "TestID","CCID","BWPID","Slot","Symbol","RB","Port","Channel", ...
    "Direction","CollisionFlag","ReservedReason","Status"]);
end

function allocation = localVectorAllocation(row)
mapping = "";
if any(string(row.Channel) == ["PDSCH", "PUSCH"])
    mapping = "A";
end
start = [];
count = [];
if isfinite(row.StartSymbol)
    start = row.StartSymbol;
end
if isfinite(row.NumSymbols)
    count = row.NumSymbols;
end
allocation = sixgr.phy.frame.ResourceAllocationValidator.makeAllocation( ...
    row.Channel, row.Direction, "CCID", 0, "BWPID", 0, ...
    "AbsoluteSlot", 0, "StartSymbol", start, "NumSymbols", count, ...
    "MappingType", mapping, "StartRB", 0, "NumRB", 1, ...
    "TestID", row.TestID);
end

function [state, conflict] = localAllocationState(symbolMap, decisions)
map = char(symbolMap);
resolved = strings(1, numel(map));
resolved(map == 'D') = "D";
resolved(map == 'U') = "U";
resolved(map == 'F') = "UNRESOLVED_FLEX";
state = struct("DuplexMode", "TDD", ...
    "CommonDirection", map, "DedicatedDirection", strings(size(map)), ...
    "SymbolDirection", map, "ResolvedDirection", resolved, ...
    "ResolutionSource", strings(size(map)), ...
    "AllocationOwner", strings(size(map)));
conflict = "";
decisions = strtrim(string(decisions));
if ismissing(decisions) || any(decisions == ["", "none", "unresolved"])
    return;
end
parts = split(decisions, ";");
for index = 1:numel(parts)
    token = split(parts(index), ":");
    direction = token(1);
    bounds = split(token(2), "-");
    first = str2double(bounds(1));
    last = first;
    if numel(bounds) == 2
        last = str2double(bounds(2));
    end
    request = struct("AbsoluteSlot", 0, "StartSymbol", first, ...
        "NumSymbols", last - first + 1, "Direction", direction, ...
        "Channel", "vector_runtime", "DecisionSource", "test_vector");
    try
        state = sixgr.phy.frame.FlexibleSymbolAllocator.allocate(state, request);
    catch cause
        if string(cause.identifier) == ...
                "sixgr:phy:frame:ConflictingFlexibleSymbolResolution"
            conflict = "conflicting_flexible_symbol_resolution";
            return;
        end
        rethrow(cause);
    end
end
end

function tableOut = localOFDMRoundtrip(vectorDirectory)
vectors = readtable(fullfile(vectorDirectory, ...
    "frame_carrier_grid_test_vectors.csv"), "TextType", "string");
mask = false(height(vectors), 1);
for index = 1:height(vectors)
    mask(index) = localTruth(vectors.ExpectedValid(index));
end
vectors = vectors(mask, :);
n = height(vectors) + 1;
rows = repmat(localEmptyOFDMRow(), n, 1);
for index = 1:height(vectors)
    state = sixgr.phy.frame.CarrierGridConfig.resolve( ...
        "Role", vectors.Role(index), ...
        "FrequencyRange", vectors.FrequencyRange(index), ...
        "CenterFrequencyHz", ...
            double(vectors.RepresentativeCenterFrequency_Hz(index)), ...
        "ChannelBandwidthMHz", double(vectors.ChannelBandwidth_MHz(index)), ...
        "SubcarrierSpacingKHz", double(vectors.CarrierSCS_kHz(index)));
    rows(index) = localRunOFDMPoint( ...
        string(vectors.TestID(index)), state, index);
end
extended = sixgr.phy.frame.CarrierGridConfig.resolve( ...
    "Role", "gNB", "FrequencyRange", "FR1", ...
    "CenterFrequencyHz", 4e9, ...
    "ChannelBandwidthMHz", 20, "SubcarrierSpacingKHz", 60, ...
    "CyclicPrefix", "extended");
rows(end) = localRunOFDMPoint("OFDM-EXTENDED-CP-60", extended, 6002);
tableOut = struct2table(rows);
end

function row = localRunOFDMPoint(testID, state, seed)
carrier = nrCarrierConfig;
carrier.NCellID = 1;
carrier.NSizeGrid = state.NSizeGrid;
carrier.NStartGrid = state.NStartGrid;
carrier.SubcarrierSpacing = state.SubcarrierSpacingKHz;
carrier.CyclicPrefix = string(state.CyclicPrefix);
carrier.NSlot = 0;
carrier.NFrame = 0;

resolved = sixgr.phy.frame.OFDMSamplingResolver.resolve(state);
txGrid = localDeterministicGrid( ...
    12 * carrier.NSizeGrid, resolved.SymbolsPerSlot, seed);
[waveform, ~] = nrOFDMModulate(carrier, txGrid, ...
    "Nfft", resolved.Nfft, ...
    "SampleRate", resolved.SampleRateHz, ...
    "Windowing", resolved.WindowingSamples);
rxGrid = nrOFDMDemodulate(carrier, waveform, ...
    "Nfft", resolved.Nfft, ...
    "SampleRate", resolved.SampleRateHz);
delta = rxGrid - txGrid;
nmse = sum(abs(delta(:)).^2) / sum(abs(txGrid(:)).^2);
evm = 100 * sqrt(nmse);
valid = isequal(size(txGrid), size(rxGrid)) && ...
    resolved.WindowingSamples == 0 && nmse <= 1e-12 && evm <= 1e-4;
numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
    carrier.SubcarrierSpacing, carrier.CyclicPrefix, ...
    "generic_waveform_test", "");
row = struct( ...
    "TestID", string(testID), ...
    "Mu", double(numerology.Mu), ...
    "SCS_kHz", double(carrier.SubcarrierSpacing), ...
    "CyclicPrefix", string(carrier.CyclicPrefix), ...
    "NRB", double(carrier.NSizeGrid), ...
    "Nfft", double(resolved.Nfft), ...
    "SampleRate_Hz", double(resolved.SampleRateHz), ...
    "CPLengthsSamples", string(mat2str( ...
        resolved.CyclicPrefixLengthsPerSlot)), ...
    "WindowingSamples", double(resolved.WindowingSamples), ...
    "OccupiedBandwidth_Hz", double(resolved.OccupiedBandwidthHz), ...
    "GuardbandLow_Hz", double(state.MinimumLowGuardbandHz), ...
    "GuardbandHigh_Hz", double(state.MinimumHighGuardbandHz), ...
    "TxGridPower", mean(abs(txGrid(:)).^2), ...
    "RxGridPower", mean(abs(rxGrid(:)).^2), ...
