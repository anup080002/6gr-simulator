function code = localDirectionCode(token)
token = upper(strtrim(string(token)));
if any(token == ["D", "DL"])
    code = 1;
elseif any(token == ["U", "UL"])
    code = -1;
elseif any(token == ["F", "UNRESOLVED_FLEX", "GUARD", "UNUSED"])
    code = 0;
else
    error("sixgr:phy:frame:UnknownDirectionToken", ...
        "Unknown direction token '%s' in figure source.", token);
end
end

