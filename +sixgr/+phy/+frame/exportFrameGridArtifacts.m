function grid = localDeterministicGrid(subcarriers, symbols, seed)
grid = complex(zeros(subcarriers, symbols));
locations = unique([1, subcarriers, max(1, floor(subcarriers / 4)), ...
    max(1, floor(subcarriers / 2)), ...
    max(1, floor(3 * subcarriers / 4))]);
for location = locations
    for symbol = 1:symbols
        phaseIndex = mod(seed + 17 * location + 29 * symbol, 16);
        grid(location, symbol) = exp(1j * 2 * pi * phaseIndex / 16);
    end
end
end

