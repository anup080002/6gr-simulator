function tf = localShortcutAuditPrefilter(checkID, source)
text = lower(source);
switch string(checkID)
    case "SHORTCUT-01"
        tf = (contains(text, "strrep") || contains(text, "replace")) && ...
            contains(text, "f") && contains(text, "d");
    case "SHORTCUT-02"
        tf = contains(text, "configuredgridnumrbs") || ...
            contains(text, "configured_grid_no_standard_bandwidth_scs_match");
    case "SHORTCUT-03"
        tf = contains(text, "fr2-2") && contains(text, "fr3");
    case "SHORTCUT-04"
        tf = contains(text, "nextpow2");
    case "SHORTCUT-05"
        tf = contains(text, "12/1/1") || contains(text, "7/0/7") || ...
            ~isempty(regexp(text, ...
            '\[\s*(?:12\s*,\s*1\s*,\s*1|7\s*,\s*0\s*,\s*7)\s*\]', ...
            'once'));
    case "SHORTCUT-06"
        tf = contains(text, "dddsu");
    case "SHORTCUT-07"
        tf = contains(text, "pdsch") && contains(text, "coreset") && ...
            (contains(text, "startsymbol") || ...
             contains(text, "symbolallocation"));
    case "SHORTCUT-08"
        tf = contains(text, "pusch") && ...
            contains(text, "symbolallocation") && ...
            (contains(text, "[0 14]") || ...
             contains(text, "symbolsperslot"));
    case "SHORTCUT-09"
        tf = contains(text, ".025") || contains(text, "2.5");
    case "SHORTCUT-10"
        tf = contains(text, "clampnsizegrid") || ...
            contains(text, "wavegenwithclamp") || ...
            (contains(text, "ssb") && contains(text, "nsizegrid") && ...
             (contains(text, "clamp") || contains(text, "retry")));
    case "SHORTCUT-11"
        tf = contains(text, "prach") && contains(text, "a1") && ...
            (contains(text, "unknown") || contains(text, "fallback"));
    case "SHORTCUT-12"
        tf = contains(text, "catch") && contains(text, "legacy") && ...
            (contains(text, "resolve") || contains(text, "resolver"));
    case "SHORTCUT-13"
        tf = (contains(text, "isempty") && contains(text, "prb")) || ...
            contains(text, "[0 14]") || contains(text, "symbols = 0:13") || ...
            contains(text, "symbols=0:13");
    otherwise
        tf = true;
end
end

function [starts, matches] = localCanonicalLegacyFallbackMatches(source)
starts = zeros(1, 0);
matches = cell(1, 0);
lines = regexp(source, '\r\n|\n|\r', 'split');
lineStarts = [1, regexp(source, '\r\n|\n|\r', 'end') + 1];
if numel(lineStarts) > numel(lines)
    lineStarts = lineStarts(1:numel(lines));
end
lowerLines = lower(string(lines));
for lineIndex = 1:numel(lines)
    if isempty(regexp(char(lowerLines(lineIndex)), ...
            '^\s*catch(?:\s+\w+)?\s*$', 'once'))
        continue;
    end
    [window, original] = localAuditLineWindow( ...
        lowerLines, lines, lineIndex, 0, 12);
    hasLegacyResolverCall = ~isempty(regexp(window, ...
        "\b(?:\w*legacy\w*(?:resolver|resolve)\w*|" + ...
        "\w*(?:resolver|resolve)\w*legacy\w*)\s*\(", 'once'));
    if hasLegacyResolverCall || ...
            contains(window, "canonical_to_legacy_fallback")
        starts(end + 1) = lineStarts(lineIndex); %#ok<AGROW>
        matches{end + 1} = original; %#ok<AGROW>
    end
end
end

function [starts, matches] = localMissingAllocationShortcutMatches(source)
% Detect only contextual fabrication of absent time/frequency allocations.
% Offsets refer to SOURCE so the caller can report exact file/line evidence.
starts = zeros(1, 0);
matches = cell(1, 0);
lines = regexp(source, '\r\n|\n|\r', 'split');
lineStarts = [1, regexp(source, '\r\n|\n|\r', 'end') + 1];
if numel(lineStarts) > numel(lines)
    lineStarts = lineStarts(1:numel(lines));
end
lowerLines = lower(string(lines));

for lineIndex = 1:numel(lines)
    line = char(lowerLines(lineIndex));

    % A missing PRB set must not be expanded to the complete carrier.
    if ~isempty(regexp(line, ...
            'if\s+isempty\s*\(\s*(?:prb|prbset|prbsetcfg)\s*\)', ...
            'once'))
        [window, original] = localAuditLineWindow( ...
            lowerLines, lines, lineIndex, 0, 12);
        if ~isempty(regexp(window, ...
                "(?:prbvec|prbset)\s*=\s*0\s*:\s*\(?\s*" + ...
                "(?:nsizegrid|ngrid|gridnumrbs)", 'once'))
            starts(end + 1) = lineStarts(lineIndex); %#ok<AGROW>
            matches{end + 1} = original; %#ok<AGROW>
        end
    end

    % A getter/catch must not inject an implicit full-slot allocation.
    if contains(line, "symbolallocation") || ...
            ~isempty(regexp(line, ...
            '^\s*(?:sa|symalloc|symbolallocation)\s*=', 'once'))
        [window, original] = localAuditLineWindow( ...
            lowerLines, lines, lineIndex, 3, 10);
        hasFullSlot = ~isempty(regexp(window, ...
            '\[\s*0\s+14\s*\]', 'once'));
        hasImplicitContext = contains(window, "structget") || ...
            contains(window, "localobjectvalue") || ...
            contains(window, "catch") || ...
            contains(window, "isempty") || ...
            contains(window, "nargin") || ...
            contains(window, "numel");
        if hasFullSlot && hasImplicitContext
            starts(end + 1) = lineStarts(lineIndex); %#ok<AGROW>
            matches{end + 1} = original; %#ok<AGROW>
        end
    end

    % The equivalent explicit-symbol-vector rescue is also prohibited.
    if contains(line, "symbols = 0:13") || ...
            contains(line, "symbols=0:13")
        [window, original] = localAuditLineWindow( ...
            lowerLines, lines, lineIndex, 8, 4);
        if contains(window, "isempty") || contains(window, "numel") || ...
                contains(window, "catch")
            starts(end + 1) = lineStarts(lineIndex); %#ok<AGROW>
            matches{end + 1} = original; %#ok<AGROW>
        end
    end
end

if ~isempty(starts)
    [starts, uniqueIndex] = unique(starts, "stable");
    matches = matches(uniqueIndex);
end
end

function [normalized, original] = localAuditLineWindow( ...
        lowerLines, lines, anchor, before, after)
first = max(1, anchor - before);
last = min(numel(lines), anchor + after);
normalized = char(strjoin(lowerLines(first:last), " "));
original = char(strjoin(string(lines(first:last)), " "));
end

function files = localResolveAuditFiles(root, scopes)
files = strings(0, 1);
for scope = scopes(:).'
    path = fullfile(root, strrep(char(scope), "/", filesep));
    if isfile(path)
        files(end + 1, 1) = string(path); %#ok<AGROW>
    elseif isfolder(path)
        listing = dir(fullfile(path, "**", "*.m"));
        if ~isempty(listing)
            names = string(fullfile({listing.folder}, {listing.name}));
            files = [files; names(:)]; %#ok<AGROW>
        end
    end
end
files = unique(files, "stable");
relativeFiles = replace(erase(files, string(root) + filesep), ...
    filesep, "/");
excluded = endsWith(relativeFiles, ...
    "+sixgr/+phy/+frame/exportFrameGridArtifacts.m") | ...
    startsWith(relativeFiles, "+sixgr/+compat/");
files(excluded) = [];
end

