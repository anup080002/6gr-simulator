function value = localSHA256(path)
fid = fopen(path, "rb");
if fid < 0
    error("sixgr:phy:frame:ArtifactHashReadFailure", ...
        "Cannot open artifact for SHA-256: %s", path);
end
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid, Inf, "*uint8");
digest = javaMethod("getInstance", ...
    "java.security.MessageDigest", "SHA-256");
digest.update(bytes);
signed = digest.digest();
hex = dec2hex(mod(double(signed), 256), 2).';
value = lower(string(hex(:).'));
clear cleanup;
end

