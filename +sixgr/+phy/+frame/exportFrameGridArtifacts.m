function output = localNormalizeTestSummary(input)
required = ["Suite","TestsRun","Passed","Failed","Skipped", ...
    "Blocked","Status","ResultFile"];
if ~all(ismember(required, string(input.Properties.VariableNames)))
    error("sixgr:phy:frame:InvalidFrameGridTestSummary", ...
        "TestSummary lacks one or more required columns: %s.", ...
        strjoin(required, ", "));
end
output = input(:, cellstr(required));
output.Suite = string(output.Suite);
output.Status = upper(string(output.Status));
output.ResultFile = string(output.ResultFile);
valid = output.TestsRun > 0 & output.Passed == output.TestsRun & ...
    output.Failed == 0 & output.Skipped == 0 & output.Blocked == 0 & ...
    output.Status == "PASS";
output.Status(~valid) = "FAIL";
end

