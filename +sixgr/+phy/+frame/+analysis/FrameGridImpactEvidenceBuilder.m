classdef FrameGridImpactEvidenceBuilder
    %FRAMEGRIDIMPACTEVIDENCEBUILDER Build exact source-backed impact tables.

    methods (Static)
        function [tables, evidence, records] = build( ...
                matrixPath, rulesPath, vectorRoot, baseDir, cfg, ...
                runID, baseVerifierExit)
            matrix = localReadStrings(matrixPath);
            rules = localReadStrings(rulesPath);
            contract = localReadStrings(fullfile(vectorRoot, ...
                "desired_frame_impact_csv_contract.csv"));
            localValidate(matrix, rules, cfg);

            records = repmat(localEmptyRecord(), height(matrix), 1);
            sourceCache = struct();
            for index = 1:height(matrix)
                sourceName = string(matrix.SourceCSV(index));
                field = matlab.lang.makeValidName(sourceName);
                if ~isfield(sourceCache, field)
                    path = fullfile(baseDir, sourceName);
                    sourceCache.(field) = struct( ...
                        "Table", localReadStrings(path), ...
                        "Hash", localFileHash(path));
                end
                source = sourceCache.(field);
                records(index) = localExecute( ...
                    matrix(index, :), source.Table, source.Hash, cfg);
            end

            raw = localRaw(records, contract, runID);
            operating = localOperating(records, contract, runID);
            effects = localEffects(records, contract, runID);
            ruleTable = localRules(records, rules, effects, contract, runID);

            tables = struct();
            tables.frame_impact_run_manifest = localManifest( ...
                matrixPath, rulesPath, baseDir, baseVerifierExit, ...
                contract, runID, cfg);
            tables.frame_impact_raw_trials = raw;
            tables.frame_impact_operating_points = operating;
            tables.frame_impact_pairwise_effects = effects;
            tables.frame_impact_rule_evaluation = ruleTable;
            tables.frame_impact_numerology = localSpecialized( ...
                records, "F01", "frame_impact_numerology.csv", ...
                contract, runID, false);
            tables.frame_impact_carrier_grid = localSpecialized( ...
                records, "F02", "frame_impact_carrier_grid.csv", ...
                contract, runID, false);
            tables.frame_impact_ofdm = localSpecialized( ...
                records, ["F03","F10"], "frame_impact_ofdm.csv", ...
                contract, runID, true);
            tables.frame_impact_tdd = localSpecialized( ...
                records, ["F04","F05"], "frame_impact_tdd.csv", ...
                contract, runID, true);
            tables.frame_impact_fdd = localSpecialized( ...
                records, "F06", "frame_impact_fdd.csv", ...
                contract, runID, false);
            tables.frame_impact_allocation = localSpecialized( ...
                records, "F07", "frame_impact_allocation.csv", ...
                contract, runID, false);
            tables.frame_impact_ssb = localSpecialized( ...
                records, "F08", "frame_impact_ssb.csv", ...
                contract, runID, false);
            tables.frame_impact_prach = localSpecialized( ...
                records, "F09", "frame_impact_prach.csv", ...
                contract, runID, false);
            tables.frame_impact_bwp_cc_timing = localSpecialized( ...
                records, ["F11","F12"], ...
                "frame_impact_bwp_cc_timing.csv", ...
                contract, runID, true);
            tables.frame_impact_summary = localSummary( ...
                records, rules, ruleTable, effects, contract, runID);

            hard = upper(string(rules.Severity)) == "HARD";
            hardIDs = string(rules.RuleID(hard));
            hardRows = ruleTable(ismember( ...
                string(ruleTable.RuleID), hardIDs), :);
            evidence = struct( ...
                "ExperimentCount", height(matrix), ...
                "CompletedCount", numel(records), ...
                "FamilyCount", numel(unique(string(matrix.FamilyID))), ...
                "PairCount", numel(unique(string(matrix.PairID))), ...
                "RuleCount", height(rules), ...
                "HardRuleCount", nnz(hard), ...
                "HardRulePassCount", nnz(localTruth(hardRows.Passed)), ...
                "IncompleteCount", 0, ...
                "HardRulesPassed", all(localTruth(hardRows.Passed)), ...
                "ExecutionBackend", string(cfg.evidence.execution_backend), ...
                "ApproximationMode", string(cfg.evidence.approximation_mode), ...
                "TruthQualified", false);
        end
    end
end

function localValidate(matrix, rules, cfg)
if height(matrix) ~= 36 || ...
        numel(unique(string(matrix.ExperimentID))) ~= 36
    error("sixgr:frame:ImpactMatrixInvalid", ...
        "Frame-grid impact matrix must contain 36 unique experiments.");
end
if numel(unique(string(matrix.FamilyID))) ~= 12 || ...
        numel(unique(string(matrix.PairID))) ~= 12
    error("sixgr:frame:ImpactMatrixInvalid", ...
        "Frame-grid impact matrix must cover 12 families and pairs.");
end
if height(rules) ~= 24 || numel(unique(string(rules.RuleID))) ~= 24
    error("sixgr:frame:ImpactRulesInvalid", ...
        "Frame-grid impact pack must contain 24 unique rules.");
end
required = [ ...
    "evidence.execution_backend","evidence.approximation_mode", ...
    "evidence.truth_qualified","execution.required_experiments", ...
    "execution.required_families","execution.required_rules", ...
    "images.width_pixels","images.height_pixels", ...
    "images.resolution_dpi"];
for path = required
    if isempty(sixgr.util.structGet(cfg, path, []))
        error("sixgr:frame:ImpactStudyConfigInvalid", ...
            "StudyConfig requires field %s.", path);
    end
end
if logical(cfg.evidence.truth_qualified)
    error("sixgr:frame:ImpactTruthRelabelForbidden", ...
        "Comparative frame-grid evidence cannot claim waveform truth.");
end
end

function record = localExecute(row, source, sourceHash, cfg)
if isempty(source)
    error("sixgr:frame:ImpactSourceEmpty", ...
        "Source %s contains no executed rows.", row.SourceCSV);
end
if ~ismember("Status", string(source.Properties.VariableNames))
    error("sixgr:frame:ImpactSourceInvalid", ...
        "Source %s lacks Status.", row.SourceCSV);
end
sourcePass = all(upper(string(source.Status)) == "PASS");
if logical(cfg.execution.require_all_source_rows_pass) && ~sourcePass
    error("sixgr:frame:ImpactSourceFailed", ...
        "Source %s contains non-PASS production rows.", row.SourceCSV);
end
[observed, rowKey, sourceRows, typedError] = localObservation( ...
    source, string(row.Metric), string(row.Selection), ...
    string(row.Aggregation));
if ~isfinite(observed)
    error("sixgr:frame:ImpactObservationInvalid", ...
        "Experiment %s produced a nonfinite observation.", ...
        row.ExperimentID);
end
record = struct( ...
    "ExperimentID", string(row.ExperimentID), ...
    "FamilyID", string(row.FamilyID), ...
    "PairID", string(row.PairID), ...
    "Variant", string(row.Variant), ...
    "WorkItem", str2double(string(row.WorkItem)), ...
    "Title", string(row.Title), ...
    "SourceCSV", string(row.SourceCSV), ...
    "SourceRowKey", rowKey, ...
    "SourceCSV_SHA256", sourceHash, ...
    "Metric", string(row.Metric), ...
    "Aggregation", string(row.Aggregation), ...
    "ObservedValue", observed, "SourceRows", sourceRows, ...
    "SourceRowsPass", sourcePass, "TypedError", typedError, ...
    "ExecutionBackend", string(cfg.evidence.execution_backend), ...
    "ApproximationMode", string(cfg.evidence.approximation_mode), ...
    "TruthQualified", false, "Status", "PASS");
end

function [observed, rowKey, sourceRows, typedError] = localObservation( ...
        source, metric, selection, aggregation)
if ~ismember("TestID", string(source.Properties.VariableNames))
    error("sixgr:frame:ImpactSourceInvalid", ...
        "Frame-grid source lacks TestID lineage.");
end
groups = unique(string(source.TestID), "stable");
values = nan(numel(groups), 1);
counts = zeros(numel(groups), 1);
errors = strings(numel(groups), 1);
for index = 1:numel(groups)
    rows = source(string(source.TestID) == groups(index), :);
    counts(index) = height(rows);
    values(index) = localAggregate(rows, metric, aggregation);
    errors(index) = localTypedError(rows);
end
finite = isfinite(values);
groups = groups(finite);
counts = counts(finite);
errors = errors(finite);
values = values(finite);
if isempty(values)
    error("sixgr:frame:ImpactObservationInvalid", ...
        "No finite executed value exists for metric %s.", metric);
end
[values, order] = sort(values);
groups = groups(order);
counts = counts(order);
errors = errors(order);
switch lower(selection)
    case "low"
        selected = 1;
    case "mid"
        selected = ceil(numel(values) / 2);
    case "high"
        selected = numel(values);
    otherwise
        error("sixgr:frame:ImpactSelectionInvalid", ...
            "Unknown frame-grid impact selection %s.", selection);
end
observed = values(selected);
rowKey = groups(selected);
sourceRows = counts(selected);
typedError = errors(selected);
end

function value = localAggregate(rows, metric, aggregation)
switch lower(aggregation)
    case "direction_dl_fraction"
        values = upper(string(rows.(char(metric))));
        value = nnz(values == "D") / max(numel(values), 1);
    case "dedicated_override_fraction"
        values = lower(string(rows.(char(metric))));
        value = nnz(startsWith(values, "dedicated")) / ...
            max(numel(values), 1);
    case "valid_fraction"
        value = mean(double(localTruth(rows.(char(metric)))));
    case "value_quantile"
        values = str2double(string(rows.(char(metric))));
        values = values(isfinite(values));
        if isempty(values)
            value = NaN;
        else
            value = mean(values);
        end
    otherwise
        error("sixgr:frame:ImpactAggregationInvalid", ...
            "Unknown aggregation %s.", aggregation);
end
end

function value = localTypedError(rows)
value = "";
for candidate = ["ErrorID","ReasonCode"]
    if ismember(candidate, string(rows.Properties.VariableNames))
        tokens = string(rows.(char(candidate)));
        tokens = tokens(strlength(strtrim(tokens)) > 0);
        if ~isempty(tokens)
            value = tokens(1);
            return;
        end
    end
end
end

function value = localRaw(records, contract, runID)
value = localTable(contract, "frame_impact_raw_trials.csv", numel(records));
for index = 1:numel(records)
    r = records(index);
    value = localAssign(value, index, struct( ...
        "RunID", runID, "ExperimentID", r.ExperimentID, ...
        "FamilyID", r.FamilyID, "PairID", r.PairID, ...
        "Variant", r.Variant, "WorkItem", r.WorkItem, ...
        "Title", r.Title, "SourceCSV", r.SourceCSV, ...
        "SourceRowKey", r.SourceRowKey, ...
        "SourceCSV_SHA256", r.SourceCSV_SHA256, ...
        "Metric", r.Metric, "Aggregation", r.Aggregation, ...
        "ObservedValue", r.ObservedValue, ...
        "SourceRows", r.SourceRows, ...
        "SourceRowsPass", r.SourceRowsPass, ...
        "TypedError", r.TypedError, ...
        "ExecutionBackend", r.ExecutionBackend, ...
        "ApproximationMode", r.ApproximationMode, ...
        "TruthQualified", false, "Status", "PASS"));
end
end

function value = localOperating(records, contract, runID)
value = localTable(contract, ...
    "frame_impact_operating_points.csv", numel(records));
for index = 1:numel(records)
    r = records(index);
    value = localAssign(value, index, struct( ...
        "RunID", runID, "ExperimentID", r.ExperimentID, ...
        "FamilyID", r.FamilyID, "PairID", r.PairID, ...
        "Variant", r.Variant, "Metric", r.Metric, ...
        "ObservedValue", r.ObservedValue, ...
        "CILower", r.ObservedValue, "CIUpper", r.ObservedValue, ...
        "SourceRows", r.SourceRows, "Incomplete", false, ...
        "StopReason", "complete_deterministic_component_observation", ...
        "Status", "PASS"));
