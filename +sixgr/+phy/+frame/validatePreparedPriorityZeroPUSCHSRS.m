function evidence=validatePreparedPriorityZeroPUSCHSRS(srs,pusch)
%VALIDATEPREPAREDPRIORITYZEROPUSCHSRS Check frozen same-UE waveforms.
assert(isa(srs,'sixgr.link.PreparedUplinkControlTransmission') && ...
    srs.Channel=="SRS" && isa(pusch,'sixgr.link.PreparedDataTransmission') && ...
    pusch.Direction=="UL", ...
    'sixgr:phy:frame:PreparedSRSPUSCHRequired', ...
    'Supply typed prepared SRS and UL PUSCH transmissions.');
evidence=struct('Applicable',false,'SameNominalSlot',false, ...
    'ExactToolboxAllocation',false,'OverlapRECount',0, ...
    'Authority',"TS38.214_6.2.1_priority0_same_UE_carrier_slot");
srsStart=localNominalStart(srs.PhysicalTiming,srs.StartSample);
puschStart=localNominalStart(pusch.PhysicalTiming,pusch.StartSample);
if srsStart~=puschStart
    return;
end
evidence.SameNominalSlot=true;
a=srs.Tx.Carrier;
b=pusch.Tx.Carrier;
assert(a.NCellID==b.NCellID && a.NSizeGrid==b.NSizeGrid && ...
    a.NStartGrid==b.NStartGrid && a.SubcarrierSpacing==b.SubcarrierSpacing && ...
    srs.SampleRateHz==pusch.SampleRateHz, ...
    'sixgr:phy:frame:PreparedSRSPUSCHCarrierMismatch', ...
    'Same-UE priority validation requires one carrier and sample clock.');
priority=double(sixgr.util.structGet(pusch.ReceiverConfig, ...
    'phy.pusch.priorityIndex',NaN));
source=string(sixgr.util.structGet(pusch.ReceiverConfig, ...
    'phy.pusch.priorityIndexSource',""));
assert(isscalar(priority) && isfinite(priority) && any(priority==[0 1]) && ...
    isscalar(source) && strlength(source)>0, ...
    'sixgr:phy:frame:MissingPUSCHPriorityAuthority', ...
    'Prepared PUSCH/SRS coexistence requires installed priority authority.');
if priority~=0
    error('sixgr:phy:frame:PreparedPriorityOneSRSPUSCHUnsupported', ...
        ['Priority-1 PUSCH/SRS cancellation needs an explicit prepared-' ...
         'waveform implementation; it is not inferred here.']);
end
srsAllocation=sixgr.phy.frame.ChannelAllocationMaterializer. ...
    materializeReferenceSignal(a,'SRS',srs.Tx.SRS);
puschAllocation=sixgr.phy.frame.ChannelAllocationMaterializer. ...
    materializePUSCH(b,pusch.Tx.PUSCH);
srsCoordinates=unique(double( ...
    srsAllocation.ActualCoordinates0Based(:,1:2)),'rows');
puschCoordinates=unique(double( ...
    puschAllocation.ActualCoordinates0Based(:,1:2)),'rows');
srsSymbols=reshape(unique(srsCoordinates(:,2)),1,[]);
puschSymbols=reshape(unique(puschCoordinates(:,2)),1,[]);
sixgr.phy.frame.assertPriorityZeroPUSCHBeforeSRS( ...
    puschSymbols,srsSymbols,a.SymbolsPerSlot);
evidence.Applicable=true;
evidence.ExactToolboxAllocation=true;
evidence.PriorityIndex=priority;
evidence.PriorityIndexSource=source;
evidence.PUSCHSymbols0Based=puschSymbols;
evidence.SRSSymbols0Based=srsSymbols;
evidence.OverlapRECount=size(intersect( ...
    srsCoordinates,puschCoordinates,'rows'),1);
end

function value=localNominalStart(timing,fallback)
value=double(sixgr.util.structGet(timing,'NominalStartSample',fallback));
validateattributes(value,{'numeric'}, ...
    {'scalar','real','finite','integer','nonnegative'});
end
