classdef SSBAcquisitionWindow
% Receiver-domain initial acquisition extent, independent of the TX bitmap.
% The configured broadcast archive is retained separately. This contract
% does not shorten transmission, imply detection, or backdate availability.
methods (Static)
    function contract=create(cfg,fs,first,archiveSamples)
        validateattributes(fs,{'double'},{'scalar','real','finite','positive'});
        validateattributes(first,{'double'},{'scalar','real','finite','integer','nonnegative'});
        validateattributes(archiveSamples,{'double'},{'scalar','real','finite','integer','positive'});
        timing=sixgr.phy.frame.SSBTimingResolver.resolveFromConfig(cfg);
        [guard,guardSource]=sixgr.phy.sync.resolveTimingSearchGuard(cfg,fs);
        ticksPerSample=double(sixgr.phy.frame.AbsoluteTime.TicksPerSecond)/fs;
        assert(ticksPerSample==fix(ticksPerSample), ...
            'sixgr:phy:frame:AcquisitionSampleClock','SSB windows require an integral Tc sample clock.');
        frameSamples=double(sixgr.phy.frame.AbsoluteTime.TicksPerFrame)/ticksPerSample;
        assert(frameSamples==fix(frameSamples) && timing.HalfFrameIndex==0 && ...
            first<flintmax && mod(first,frameSamples)==0 && first+archiveSamples<=flintmax, ...
            'sixgr:phy:frame:UnsupportedAcquisitionOrigin', ...
            ['This bounded acquisition contract requires a declared frame-aligned phase-zero ' ...
             'capture origin; it is not an unknown-frame-phase search.']);
        symbols=double(timing.CandidateStartSymbolsWithinHalfFrame(:).');
        stop=zeros(size(symbols));
        for k=1:numel(symbols)
            ending=symbols(k)+4;
            clock=sixgr.phy.frame.AbsoluteTime.fromAbsoluteSlotSymbol( ...
                floor(ending/14),mod(ending,14),timing.Mu);
            assert(rem(clock.Ticks,int64(ticksPerSample))==0, ...
                'sixgr:phy:frame:AcquisitionSampleClock','The complete candidate must end on a receive sample.');
            stop(k)=double(clock.Ticks)/ticksPerSample;
        end
        extent=max(stop)+double(guard);
        assert(extent<=archiveSamples, ...
            'sixgr:phy:frame:AcquisitionWindowOutsideArchive', ...
            'The original archive must cover every receiver-supported candidate and configured timing guard.');
        contract=struct('ContractVersion',"sixgr.ssb.initial_acquisition_window/v1", ...
            'Scope',"all_receiver_case_lmax_candidates_not_TX_active_bitmap", ...
            'Case',string(timing.Case),'Lmax',double(timing.Lmax), ...
            'HalfFrameIndex',double(timing.HalfFrameIndex),'FrameSamples',frameSamples, ...
            'AbsoluteFrameNumber',first/frameSamples, ...
            'OriginScope',"declared_frame_aligned_zero_origin_runtime_epoch_not_received_timing", ...
            'CandidateIndices',double(timing.CandidateIndices(:).'), ...
            'CandidateStartSymbolsWithinHalfFrame',symbols, ...
            'CandidateEndSamplesExclusive',stop, ...
            'TimingGuardSamples',double(guard),'TimingGuardSource',string(guardSource), ...
            'SampleRateHz',fs,'StartSample',first,'EndSampleExclusive',first+extent, ...
            'ArchiveEndSampleExclusive',first+archiveSamples, ...
            'ReceiverGridRelationship',timing.GridRelationship, ...
            'DeliveryPolicy',"next_canonical_slot_boundary_after_complete_capture_no_extra_processing_delay");
        contract.SHA256=sixgr.phy.waveform.WaveformHash.bytes(getByteStreamFromArray(contract));
    end
    function validate(contract,cfg,fs,first,archiveSamples)
        expected=sixgr.phy.frame.SSBAcquisitionWindow.create(cfg,fs,first,archiveSamples);
        assert(isequaln(contract,expected), ...
            'sixgr:phy:frame:ChangedAcquisitionWindow', ...
            'Retain the original complete receiver search domain, guard, tuning, archive and sample clock.');
    end
end
end
