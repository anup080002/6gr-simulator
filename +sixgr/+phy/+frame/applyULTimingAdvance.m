function result = applyULTimingAdvance(waveform, source)
%APPLYULTIMINGADVANCE Apply an explicit UL timing advance to a waveform.
%
% A positive timing-advance command moves the UE waveform earlier by the
% configured number of samples. The operation preserves waveform length
% and zero pads samples exposed at the end. No timing value is inferred.

if ~(isnumeric(waveform) || islogical(waveform)) || ndims(waveform) > 2
    error("sixgr:phy:frame:InvalidULTimingWaveform", ...
        "UL timing advance requires a numeric vector or 2-D waveform.");
end

if isa(source, "sixgr.phy.frame.FDDCarrierContexts")
    context = source.context("UL");
    samples = double(context.TimingAdvanceSamples);
    sourceID = string(context.GridID);
elseif isstruct(source) && isscalar(source)
    direction = upper(string(sixgr.util.structGet(source, ...
        "Direction", "")));
    if direction ~= "UL"
        error("sixgr:phy:frame:ULTimingAdvanceRequiresULContext", ...
            "Timing advance requires an explicit UL carrier context.");
    end
    samples = double(sixgr.util.structGet(source, ...
        "TimingAdvanceSamples", NaN));
    sourceID = string(sixgr.util.structGet(source, ...
        "GridID", "explicit_ul_context"));
elseif isnumeric(source) && isreal(source) && isscalar(source)
    samples = double(source);
    sourceID = "explicit_sample_count";
else
    error("sixgr:phy:frame:InvalidULTimingAdvanceSource", ...
        "Timing advance source must be FDDCarrierContexts, an UL context, or an explicit sample count.");
end

if ~(isscalar(samples) && isfinite(samples) && ...
        samples >= 0 && samples == round(samples))
    error("sixgr:phy:frame:InvalidULTimingAdvance", ...
        "UL timing advance must be an explicit nonnegative integer sample count.");
end

result = struct( ...
    "InputWaveform", waveform, ...
    "Waveform", sixgr.util.applyFractionalSampleDelay(waveform, -samples), ...
    "Direction", "UL", ...
    "TimingAdvanceSamples", samples, ...
    "TimingAdvanceApplied", samples > 0, ...
    "LengthPreserved", true, ...
    "Source", sourceID, ...
    "SignConvention", "positive_command_advances_ul_waveform");
end
