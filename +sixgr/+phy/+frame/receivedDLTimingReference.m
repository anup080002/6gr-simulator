function reference = receivedDLTimingReference(cfg, recovered, observation, filterDelaySamples)
% Received SS/PBCH timing, calibrated only for implementation filter delay.
% No TX waveform, geometry, true path delay, or configured SSB index is used.
% This adapter uses the runtime's zero-origin radio epoch: lab frame zero is
% SFN zero. An arbitrary standalone capture with an unknown radio epoch is
% not interchangeable with this unwrapped runtime clock.
assert(isstruct(recovered) && isscalar(recovered) && ...
    all(isfield(recovered,{'BCHCrcPass','MIBDecoded','TimingOffset','SampleRateHz', ...
    'MIBSystemFrameNumber','MIBHalfFrameBit','MIBSSBIndex','SSBIndex','NCellID'})), ...
    'sixgr:phy:frame:InvalidReceivedDLTiming','Received timing fields are missing.');
assert(islogical(recovered.BCHCrcPass) && isscalar(recovered.BCHCrcPass) && ...
    islogical(recovered.MIBDecoded) && isscalar(recovered.MIBDecoded) && ...
    recovered.BCHCrcPass && recovered.MIBDecoded, ...
    'sixgr:phy:frame:UndecodedDLTiming','A CRC-valid received BCH is required.');
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && isscalar(observation), ...
    'sixgr:phy:frame:InvalidReceivedDLTiming','Use the original typed received observation.');
assert(observation.isComplete(),'WAVEFORM:IncompleteObservation','Complete the actual SSB capture first.');
fs = observation.SampleRateHz;
localInteger(filterDelaySamples,0,flintmax,'Implementation filter delay');
localInteger(recovered.TimingOffset,0,flintmax,'Received timing offset');
localInteger(recovered.MIBSystemFrameNumber,0,1023,'Received SFN');
localInteger(recovered.MIBHalfFrameBit,0,1,'Received half-frame bit');
localInteger(recovered.MIBSSBIndex,0,63,'Decoded SSB index');
localInteger(recovered.SSBIndex,0,63,'Observed SSB index');
localInteger(recovered.NCellID,0,1007,'Received physical cell ID');
localInteger(observation.StartSample,0,flintmax,'Observation start');
localInteger(observation.EndSampleExclusive,1,flintmax,'Observation end');
assert(isnumeric(recovered.SampleRateHz) && isreal(recovered.SampleRateHz) && ...
    isscalar(recovered.SampleRateHz) && isfinite(recovered.SampleRateHz) && recovered.SampleRateHz>0, ...
    'sixgr:phy:frame:InvalidReceivedDLTiming','Received sample rate must be a finite positive numeric scalar.');
assert(recovered.TimingOffset<observation.EndSampleExclusive-observation.StartSample, ...
    'sixgr:phy:frame:InvalidReceivedDLTiming','Received SSB timing must lie inside its original capture.');
assert(recovered.SampleRateHz==fs && recovered.SSBIndex==recovered.MIBSSBIndex, ...
    'sixgr:phy:frame:InconsistentReceivedSSBTiming','BCH index and observation clocks disagree.');
timing = sixgr.phy.frame.SSBTimingResolver.resolveFromConfig(cfg, ...
    'SSBIndex',recovered.MIBSSBIndex,'HalfFrameIndex',recovered.MIBHalfFrameBit);
symbol = timing.SelectedStartSymbol;
position = sixgr.phy.frame.AbsoluteTime.fromAbsoluteSlotSymbol( ...
    floor(symbol/14),mod(symbol,14),timing.Mu);
ticksPerSample = double(sixgr.phy.frame.AbsoluteTime.TicksPerSecond)/fs;
assert(isfinite(ticksPerSample) && ticksPerSample>=1 && ticksPerSample<=flintmax && ...
    ticksPerSample==fix(ticksPerSample) && rem(position.Ticks,int64(ticksPerSample))==0 && ...
    rem(sixgr.phy.frame.AbsoluteTime.TicksPerFrame,int64(ticksPerSample))==0, ...
    'sixgr:phy:frame:DLReferenceOffSampleClock','SSB timing must lie on the actual sample clock.');
withinFrame = double(position.Ticks)/ticksPerSample;
frameSamples = double(sixgr.phy.frame.AbsoluteTime.TicksPerFrame)/ticksPerSample;
frameOrigin = observation.StartSample + double(recovered.TimingOffset) - double(filterDelaySamples) - withinFrame;
% The shared lab clock supplies an unwrapped epoch, not a radio phase.
% The measured phase must lie inside the declared receiver search budget.
frameNumber = round(frameOrigin/frameSamples);
phase = frameOrigin - frameNumber*frameSamples;
[guard,guardSource] = sixgr.phy.sync.resolveTimingSearchGuard(cfg,fs);
assert(abs(phase)<=guard && 2*guard<frameSamples, ...
    'sixgr:phy:frame:UnresolvedDLReferenceEpoch','Received timing is outside the declared unambiguous search window.');
localInteger(frameNumber,0,flintmax,'Unwrapped received frame');
% TS 38.331 MIB supplies six SFN MSBs and TS 38.212 7.1.1 supplies
% four PBCH LSBs. Check the resulting ten-bit radio frame against the
% original capture epoch, never against the later result-availability time.
assert(mod(frameNumber,1024)==recovered.MIBSystemFrameNumber, ...
    'sixgr:phy:frame:ReceivedSFNClockMismatch', ...
    'Decoded SFN %d disagrees with unwrapped received frame %.0f on the zero-origin runtime clock.', ...
    recovered.MIBSystemFrameNumber,frameNumber);
reference = struct('Source',"received_SSB_timing_and_decoded_BCH", ...
    'SampleRateHz',fs,'ObservationStartSample',observation.StartSample, ...
    'AvailableAtSample',observation.EndSampleExclusive, ...
    'RawSSBTiming_samples',recovered.TimingOffset,'ImplementationFilterDelay_samples',filterDelaySamples, ...
    'SSBIndex',recovered.MIBSSBIndex,'NCellID',recovered.NCellID, ...
    'ReceivedSFN',recovered.MIBSystemFrameNumber,'ReceivedHalfFrame',recovered.MIBHalfFrameBit, ...
    'AbsoluteFrameNumber',frameNumber,'ReceivedFrameOriginSample',frameOrigin, ...
    'DLPhaseOffsetSamples',phase,'SearchGuardSamples',guard,'SearchGuardSource',guardSource, ...
    'TimingEstimator',"practical_received_PSS_synchronizer_not_true_path_delay", ...
    'WaveformTimingApplied',false);
end

function localInteger(value,minimum,maximum,label)
assert(isnumeric(value) && isreal(value) && isscalar(value) && isfinite(value) && ...
    value>=minimum && value<=maximum && value==fix(value), ...
    'sixgr:phy:frame:InvalidReceivedDLTiming', ...
    '%s must be an exact numeric integer in [%g,%g].',label,minimum,maximum);
end
