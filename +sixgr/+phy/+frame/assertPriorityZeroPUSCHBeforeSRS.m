function evidence=assertPriorityZeroPUSCHBeforeSRS(puschSymbols,srsSymbols,symbolsPerSlot)
%ASSERTPRIORITYZEROPUSCHBEFORESRS Enforce same-UE priority-0 ordering.
% Caller establishes a common carrier and slot and supplies the actual
% PUSCH/DM-RS/PT-RS and SRS OFDM symbols. The check never remaps resources.
validateattributes(symbolsPerSlot,{'numeric'}, ...
    {'scalar','real','finite','integer','positive'});
puschSymbols=localCheckedSymbols(puschSymbols,symbolsPerSlot);
srsSymbols=localCheckedSymbols(srsSymbols,symbolsPerSlot);
evidence=struct('PUSCHSymbols0Based',puschSymbols, ...
    'SRSSymbols0Based',srsSymbols, ...
    'Applicable',~isempty(puschSymbols) && ~isempty(srsSymbols), ...
    'Authority',"TS38.214_6.2.1_priority0_same_UE_carrier_slot", ...
    'AllocationChanged',false);
if ~evidence.Applicable
    return;
end
assert(max(puschSymbols)<min(srsSymbols), ...
    'sixgr:phy:frame:PriorityZeroPUSCHSRSOrder', ...
    ['Priority-0 PUSCH/DM-RS/PT-RS symbols %s must precede SRS ' ...
     'symbols %s. Resolve the actual allocation before DCI; do not ' ...
     'repair received samples.'],mat2str(puschSymbols),mat2str(srsSymbols));
end

function out=localCheckedSymbols(value,n)
assert(isnumeric(value) && isreal(value) && ...
    (isvector(value) || isempty(value)) && all(isfinite(value(:))) && ...
    all(value(:)==fix(value(:))) && all(value(:)>=0 & value(:)<n), ...
    'sixgr:phy:frame:InvalidSRSPUSCHSymbols', ...
    'Resource symbols must be finite zero-based integers in the actual slot.');
out=reshape(unique(double(value)),1,[]);
end
