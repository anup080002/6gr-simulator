function values = localIntegerVector(input, label)
if ~(isnumeric(input) && isreal(input) && ...
        all(isfinite(double(input(:)))) && ...
        all(double(input(:)) >= 0) && ...
        all(double(input(:)) == fix(double(input(:)))))
    error("sixgr:phy:frame:InvalidTimingPolicy", ...
        "%s must contain nonnegative integer values.", label);
end
values = reshape(double(input), 1, []);
end

function value = localNonnegativeIdentifier(input, label)
value = localNonnegativeInteger(input, label);
end

function values = localIdentifierVector(input, label)
if isnumeric(input)
    values = localIntegerVector(input, label);
elseif isstring(input) || ischar(input) || iscellstr(input)
    text = string(input(:));
    values = zeros(1, numel(text));
    for index = 1:numel(text)
        values(index) = localNumericIdentifier(text(index), label);
    end
else
    error("sixgr:phy:frame:InvalidRuntimeIdentifier", ...
        "%s must contain zero-based numeric identifiers.", label);
end
values = unique(values, "stable");
end

function values = localNumericIdentifierVector(input, label)
if isnumeric(input)
    values = localIntegerVector(input, label);
else
    text = string(input(:));
    values = zeros(1, numel(text));
    for index = 1:numel(text)
        values(index) = localNumericIdentifier(text(index), label);
    end
end
end

function value = localNumericIdentifier(input, label)
if isnumeric(input)
    value = localNonnegativeInteger(input, label);
    return;
end
text = strtrim(string(input));
number = str2double(text);
if ~(isscalar(number) && isfinite(number) && number >= 0 && ...
        number == fix(number))
    error("sixgr:phy:frame:NonserializableRuntimeIdentifier", ...
        "%s '%s' is not an explicit zero-based numeric identifier.", ...
        label, text);
end
value = double(number);
end

function value = localNonnegativeInteger(input, label)
if ~(isnumeric(input) && isreal(input) && isscalar(input) && ...
        isfinite(double(input)) && double(input) >= 0 && ...
        double(input) == fix(double(input)))
    error("sixgr:phy:frame:InvalidRuntimeInteger", ...
        "%s must be a nonnegative integer scalar.", label);
end
value = double(input);
end

function value = localPositiveInteger(input, label)
value = localNonnegativeInteger(input, label);
if value < 1
    error("sixgr:phy:frame:InvalidRuntimeInteger", ...
        "%s must be a positive integer scalar.", label);
end
end

function value = localPositiveFinite(input, label)
if ~(isnumeric(input) && isreal(input) && isscalar(input) && ...
        isfinite(double(input)) && double(input) > 0)
    error("sixgr:phy:frame:InvalidRuntimeNumber", ...
        "%s must be a positive finite scalar.", label);
end
value = double(input);
end

function value = localLogical(input, label)
if ~((islogical(input) || isnumeric(input)) && isscalar(input) && ...
        isfinite(double(input)) && any(double(input) == [0, 1]))
    error("sixgr:phy:frame:InvalidRuntimeLogical", ...
        "%s must be scalar logical.", label);
end
value = logical(input);
end

