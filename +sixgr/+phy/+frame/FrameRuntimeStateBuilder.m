classdef FrameRuntimeStateBuilder
    %FRAMERUNTIMESTATEBUILDER Build the production CC/BWP runtime snapshot.
    %
    % The builder consumes the already resolved internal simulator config,
    % constructs the canonical BWPConfig/ComponentCarrierConfig objects to
    % validate every configured grid and identity, and then returns a
    % serialization-safe snapshot.  Runtime consumers must use this
    % snapshot instead of rewriting the global carrier/numerology fields
    % when a BWP changes.

    methods (Static)
        function [snapshot, carriers] = build(cfg)
            if ~(isstruct(cfg) && isscalar(cfg))
                error("sixgr:phy:frame:InvalidRuntimeConfig", ...
                    "Frame runtime state requires one resolved internal config struct.");
            end

            carrierSpecs = localCarrierSpecs(cfg);
            carriers = cell(1, numel(carrierSpecs));
            carrierSnapshotCells = cell(numel(carrierSpecs), 1);
            bwpStates = repmat(localEmptyBWPState(), numel(carrierSpecs), 1);

            for carrierIndex = 1:numel(carrierSpecs)
                spec = carrierSpecs(carrierIndex);
                [carrierConfig, bwpConfigs] = ...
                    localMaterializeCarrier(cfg, spec, carrierIndex);
                bwpObjects = cell(1, numel(bwpConfigs));
                for bwpIndex = 1:numel(bwpConfigs)
                    direction = upper(string(bwpConfigs(bwpIndex).Direction));
                    if direction == "DL"
                        grid = carrierConfig.DLCarrierGrid;
                    else
                        grid = carrierConfig.ULCarrierGrid;
                    end
                    bwpObjects{bwpIndex} = sixgr.phy.frame.BWPConfig( ...
                        bwpConfigs(bwpIndex), grid);
                end
                carrier = sixgr.phy.frame.ComponentCarrierConfig( ...
                    carrierConfig, bwpObjects);
                carriers{carrierIndex} = carrier;
                carrierSnapshotCells{carrierIndex} = ...
                    localCarrierSnapshot(carrier, bwpObjects);
                bwpStates(carrierIndex) = ...
                    localBWPStateSnapshot(carrier, bwpObjects);
            end
            carrierSnapshots = vertcat(carrierSnapshotCells{:});

            localValidateCrossCarrierMaps(carrierSnapshots);
            identity = localDefaultIdentity(cfg, carrierSnapshots);
            policy = localTimingPolicy(cfg, carrierSnapshots, identity);
            snapshot = struct( ...
                "ContractVersion", "sixgr_frame_runtime_state/v1", ...
                "IndexConvention", "zero_based", ...
                "ComponentCarriers", carrierSnapshots, ...
                "BWPState", bwpStates, ...
                "Policy", policy, ...
                "DefaultIdentity", identity);
        end

        function cfg = attachTimingContext(cfg)
            %ATTACHTIMINGCONTEXT Attach the one canonical production view.
            %
            % If the frame structure has not yet been resolved, resolution
            % is delegated once to FrameStructureEngine.  No K value or
            % resource allocation is supplied here; configured timing rows
            % remain mandatory when a production relation is invoked.
            if ~(isstruct(cfg) && isscalar(cfg))
                error("sixgr:phy:frame:InvalidRuntimeConfig", ...
                    "Timing-context attachment requires one scalar config struct.");
            end
            existing = sixgr.util.structGet(cfg, ...
                "phy.frameStructure.TimingContext", []);
            if isstruct(existing) && isscalar(existing)
                return;
            end
            frame = sixgr.util.structGet(cfg, "phy.frameStructure", []);
            if ~(isstruct(frame) && isscalar(frame) && ...
                    isfield(frame, "CarrierGrid"))
                facade = sixgr.phy.FrameStructureEngine( ...
                    cfg, "FrameCoreOnly", true);
                frame = facade.toStruct();
                cfg = sixgr.util.structSet(cfg, ...
                    "phy.frameStructure", frame);
            end
            [snapshot, ~] = ...
                sixgr.phy.frame.FrameRuntimeStateBuilder.build(cfg);
            cfg = sixgr.util.structSet(cfg, ...
                "phy.frameStructure.TimingContext", snapshot);
            cfg = sixgr.util.structSet(cfg, ...
                "resolved_runtime_view.frame_structure.TimingContext", ...
                snapshot);
            cfg = sixgr.util.structSet(cfg, ...
                "phy.frame.ComponentCarriers", ...
                snapshot.ComponentCarriers);
            cfg = sixgr.util.structSet(cfg, ...
                "phy.frame.BWPState", snapshot.BWPState);
            cfg = sixgr.util.structSet(cfg, ...
                "phy.frame.Policy", snapshot.Policy);
            cfg = sixgr.util.structSet(cfg, ...
                "phy.frame.DefaultIdentity", snapshot.DefaultIdentity);
        end
    end
end

function specs = localCarrierSpecs(cfg)
paths = [ ...
    "phy.frame.componentCarriers", ...
    "phy.componentCarriers", ...
    "lls6g.component_carriers", ...
    "component_carriers", ...
    "phy.frame.ComponentCarriers", ...
    "phy.frameStructure.TimingContext.ComponentCarriers"];
raw = [];
for path = paths
    candidate = sixgr.util.structGet(cfg, path, []);
    if ~isempty(candidate)
        raw = candidate;
        break;
    end
end
if isempty(raw)
    specs = localDefaultCarrierSpec(cfg);
else
    specs = localStructSequence(raw, "component-carrier configuration");
end
end

function spec = localDefaultCarrierSpec(cfg)
frame = localRequiredStruct(cfg, "phy.frameStructure");
grid = localRequiredStruct(frame, "CarrierGrid");
duplex = upper(string(localFirst(cfg, [ ...
    "phy.frameStructure.DuplexMode", "phy.duplex.mode"], "")));
if ~any(duplex == ["TDD", "FDD"])
    error("sixgr:phy:frame:MissingDuplexMode", ...
        "The resolved frame structure must identify TDD or FDD.");
end

center = localPositiveFinite(localFirst(cfg, [ ...
    "phy.frameStructure.CenterFrequencyHz", ...
    "phy.carrier.centerFrequency_Hz", ...
    "phy.carrier.fc_Hz", ...
    "frequency.centerFrequencyHz"], NaN), "CenterFrequencyHz");
dlCenter = center;
ulCenter = center;
dlGrid = localGridFromCanonical(grid);
ulGrid = dlGrid;
if duplex == "FDD"
    fdd = localRequiredStruct(frame, "FDDContexts");
    downlink = localRequiredStruct(fdd, "Downlink");
    uplink = localRequiredStruct(fdd, "Uplink");
    dlCenter = localPositiveFinite(localFirstField(downlink, ...
        ["CenterFrequencyHz"], NaN), "FDD DLCenterFrequencyHz");
    ulCenter = localPositiveFinite(localFirstField(uplink, ...
        ["CenterFrequencyHz"], NaN), "FDD ULCenterFrequencyHz");
    if dlCenter == ulCenter
        error("sixgr:phy:frame:FDDRequiresSeparateFrequencies", ...
            "FDD runtime state requires distinct explicit DL and UL center frequencies.");
    end
    dlGrid = localGridFromFDD(downlink, grid);
    ulGrid = localGridFromFDD(uplink, grid);
end

band = string(localFirst(cfg, [ ...
    "lls6g.frequency.band_name", "frequency.bandName", ...
    "frequency.band_name", "phy.carrier.Band"], "configured_carrier"));
frequencyRange = string(localFirst(cfg, [ ...
    "phy.frameStructure.FrequencyRange", "phy.frequencyRange", ...
    "frequency.rangeName"], ""));
bandwidthMHz = localPositiveFinite(localFirst(cfg, [ ...
    "phy.frameStructure.BandwidthHz", "channel.bandwidth_Hz"], NaN), ...
    "ChannelBandwidth") / 1e6;
cellID = localNonnegativeIdentifier(localFirst(cfg, [ ...
    "phy.servingCellID", "phy.carrier.ServingCellID", ...
    "phy.carrier.NCellID"], 0), "ServingCellID");

spec = struct( ...
    "CCID", 0, ...
    "ServingCellID", cellID, ...
    "SchedulingCCIDs", 0, ...
    "CenterFrequencyHz", center, ...
    "DLCenterFrequencyHz", dlCenter, ...
    "ULCenterFrequencyHz", ulCenter, ...
    "Band", band, ...
    "FrequencyRange", frequencyRange, ...
    "ChannelBandwidthMHz", bandwidthMHz, ...
    "DuplexMode", duplex, ...
    "DLCarrierGrid", dlGrid, ...
    "ULCarrierGrid", ulGrid, ...
    "CarrierIndicatorMap", struct( ...
        "Indicator", 0, "ScheduledCCID", 0));
spec.BWPs = localDefaultBWPSpecs(cfg, 0, cellID, frequencyRange, ...
    dlGrid, ulGrid, duplex, localCommonTDDReferenceSCS(cfg, duplex));
end

function [carrierConfig, bwps] = localMaterializeCarrier(cfg, spec, index)
ccid = localNonnegativeIdentifier(localFirstField(spec, ...
    ["CCID", "cc_id"], index - 1), "CCID");
servingCellID = localNonnegativeIdentifier(localFirstField(spec, ...
    ["ServingCellID", "serving_cell_id"], 0), "ServingCellID");
duplex = upper(string(localFirstField(spec, ...
    ["DuplexMode", "duplex_mode"], ...
    localFirst(cfg, ["phy.duplex.mode"], ""))));
if ~any(duplex == ["TDD", "FDD"])
    error("sixgr:phy:frame:InvalidDuplexMode", ...
        "Component carrier %d must explicitly resolve TDD or FDD.", ccid);
end
center = localPositiveFinite(localFirstField(spec, ...
    ["CenterFrequencyHz", "center_frequency_hz"], ...
    localFirst(cfg, ["phy.frameStructure.CenterFrequencyHz"], NaN)), ...
    "CenterFrequencyHz");
dlCenter = localFirstField(spec, ...
    ["DLCenterFrequencyHz", "dl_center_frequency_hz"], center);
ulCenter = localFirstField(spec, ...
    ["ULCenterFrequencyHz", "ul_center_frequency_hz"], center);
if duplex == "FDD"
    if ~localHasAnyField(spec, ...
            ["DLCenterFrequencyHz", "dl_center_frequency_hz"]) || ...
            ~localHasAnyField(spec, ...
            ["ULCenterFrequencyHz", "ul_center_frequency_hz"])
        error("sixgr:phy:frame:FDDRequiresSeparateFrequencies", ...
            "FDD carrier %d requires explicit DL and UL center frequencies.", ccid);
    end
    dlCenter = localPositiveFinite(dlCenter, "DLCenterFrequencyHz");
    ulCenter = localPositiveFinite(ulCenter, "ULCenterFrequencyHz");
    if dlCenter == ulCenter
        error("sixgr:phy:frame:FDDRequiresSeparateFrequencies", ...
            "FDD carrier %d DL and UL center frequencies must be distinct.", ccid);
    end
else
    dlCenter = center;
    ulCenter = center;
end

frequencyRange = upper(string(localFirstField(spec, ...
    ["FrequencyRange", "frequency_range"], ...
    localFirst(cfg, ["phy.frameStructure.FrequencyRange"], ""))));
bandwidthMHz = localPositiveFinite(localFirstField(spec, ...
    ["ChannelBandwidthMHz", "channel_bandwidth_mhz"], ...
    localFirst(cfg, ["phy.frameStructure.BandwidthHz"], NaN) / 1e6), ...
    "ChannelBandwidthMHz");
band = string(localFirstField(spec, ["Band", "band"], ...
    localFirst(cfg, ["lls6g.frequency.band_name"], "configured_carrier")));
dlGrid = localFirstField(spec, ["DLCarrierGrid", "dl_carrier_grid"], []);
ulGrid = localFirstField(spec, ["ULCarrierGrid", "ul_carrier_grid"], []);
if isempty(dlGrid) || isempty(ulGrid)
    frameGrid = localRequiredStruct(cfg, "phy.frameStructure.CarrierGrid");
    if isempty(dlGrid)
        dlGrid = localGridFromCanonical(frameGrid);
    end
    if isempty(ulGrid)
        ulGrid = localGridFromCanonical(frameGrid);
    end
end
dlGrid = localNormalizeGrid(dlGrid);
ulGrid = localNormalizeGrid(ulGrid);

indicatorMap = localFirstField(spec, ...
    ["CarrierIndicatorMap", "carrier_indicator_map"], []);
if isempty(indicatorMap)
    indicatorMap = struct("Indicator", 0, "ScheduledCCID", ccid);
end
scheduling = localFirstField(spec, ...
    ["SchedulingCCIDs", "scheduling_cc_ids"], ccid);
carrierConfig = struct( ...
    "CCID", ccid, ...
    "ServingCellID", servingCellID, ...
    "SchedulingCCIDs", localIdentifierVector(scheduling, ...
        "SchedulingCCIDs"), ...
    "CenterFrequencyHz", center, ...
    "DLCenterFrequencyHz", dlCenter, ...
    "ULCenterFrequencyHz", ulCenter, ...
    "Band", band, ...
    "FrequencyRange", frequencyRange, ...
    "ChannelBandwidthMHz", bandwidthMHz, ...
    "DuplexMode", duplex, ...
    "DLCarrierGrid", dlGrid, ...
    "ULCarrierGrid", ulGrid);
carrierConfig.CarrierIndicatorMap = localNormalizeIndicatorMap(indicatorMap);

rawBWPs = localFirstField(spec, ...
    ["BWPs", "bwps", "BWPConfigs", "bwp_configs"], []);
if isempty(rawBWPs)
    dlRaw = localFirstField(spec, ["DLBWPs", "dl_bwps"], []);
    ulRaw = localFirstField(spec, ["ULBWPs", "ul_bwps"], []);
    if isempty(dlRaw) && isempty(ulRaw)
        bwps = localDefaultBWPSpecs(cfg, ccid, servingCellID, ...
            frequencyRange, dlGrid, ulGrid, duplex, ...
            localCommonTDDReferenceSCS(cfg, duplex));
        return;
    end
    rawBWPs = localConcatenateSequences(dlRaw, ulRaw);
end
bwps = localNormalizeBWPs(rawBWPs, ccid, servingCellID, ...
    frequencyRange, dlGrid, ulGrid, duplex, ...
    localCommonTDDReferenceSCS(cfg, duplex));
end

function value = localCommonTDDReferenceSCS(cfg, duplex)
if duplex ~= "TDD"
    value = NaN;
    return;
end
[raw, found] = localFind(cfg, [ ...
    "phy.duplex.tddCommon.ReferenceSubcarrierSpacingKHz", ...
    "phy.duplex.tddCommon.referenceSubcarrierSpacingKHz", ...
    "phy.frameStructure.SlotState.ReferenceSubcarrierSpacingKHz"]);
if ~found
    error("sixgr:phy:frame:MissingTDDCommonConfig", ...
        "TDD runtime BWP state requires the canonical common reference SCS.");
end
value = localPositiveFinite(raw, "CommonTDDReferenceSCSKHz");
end

function bwps = localDefaultBWPSpecs(cfg, ccid, servingCellID, ...
        frequencyRange, dlGrid, ulGrid, duplex, commonTDDReferenceSCS)
dlRaw = localFirst(cfg, [ ...
    "phy.bwp.configuredDL", "phy.bwp.dl"], []);
ulRaw = localFirst(cfg, [ ...
    "phy.bwp.configuredUL", "phy.bwp.ul"], []);
if isempty(dlRaw)
    dlRaw = struct();
end
if isempty(ulRaw)
    ulRaw = struct();
end
bwps = localNormalizeBWPs(localConcatenateSequences(dlRaw, ulRaw), ...
    ccid, servingCellID, frequencyRange, dlGrid, ulGrid, duplex, ...
    commonTDDReferenceSCS);
end

function bwps = localNormalizeBWPs(raw, ccid, servingCellID, ...
        frequencyRange, dlGrid, ulGrid, duplex, commonTDDReferenceSCS)
items = localStructSequence(raw, "BWP configuration");
if isempty(items)
    error("sixgr:phy:frame:EmptyBWPSet", ...
        "Every production component carrier requires configured DL and UL BWPs.");
end
directions = strings(numel(items), 1);
explicitActive = false(numel(items), 1);
active = false(numel(items), 1);
ids = zeros(numel(items), 1);
for itemIndex = 1:numel(items)
    item = items(itemIndex);
    direction = upper(string(localFirstField(item, ...
        ["Direction", "direction"], "")));
    if strlength(direction) == 0
        if itemIndex == 1
            direction = "DL";
        elseif itemIndex == 2
            direction = "UL";
        end
    end
    if ~any(direction == ["DL", "UL"])
        error("sixgr:phy:frame:InvalidBWPDirection", ...
            "Every BWP entry must identify direction DL or UL.");
    end
    directions(itemIndex) = direction;
    ids(itemIndex) = localNonnegativeIdentifier(localFirstField(item, ...
        ["BWPID", "bwp_id", "id"], 0), "BWPID");
    explicitActive(itemIndex) = localHasAnyField(item, ...
        ["ActiveInitial", "active_initial", "Active", "active"]);
    if explicitActive(itemIndex)
        active(itemIndex) = localLogical(localFirstField(item, ...
            ["ActiveInitial", "active_initial", "Active", "active"], false), ...
            "ActiveInitial");
    end
end

for direction = ["DL", "UL"]
    members = find(directions == direction);
    if isempty(members)
        grid = dlGrid;
        if direction == "UL"
            grid = ulGrid;
        end
        newItem = struct( ...
            "BWPID", 0, "Direction", direction, ...
            "NStartBWP", grid.NStartGrid, ...
            "NSizeBWP", grid.NSizeGrid);
        items(end + 1) = localUnionStruct(items, newItem); %#ok<AGROW>
        directions(end + 1) = direction; %#ok<AGROW>
        ids(end + 1) = 0; %#ok<AGROW>
        explicitActive(end + 1) = false; %#ok<AGROW>
        active(end + 1) = true; %#ok<AGROW>
        members = numel(items);
    end
    if numel(members) > 1 && ~all(explicitActive(members))
        error("sixgr:phy:frame:AmbiguousInitialBWPState", ...
            "Every %s BWP in a multi-BWP array must explicitly set ActiveInitial.", ...
            direction);
    end
    if numel(members) == 1 && ~explicitActive(members)
        active(members) = true;
    end
    if nnz(active(members)) ~= 1
        error("sixgr:phy:frame:InvalidInitialBWPState", ...
            "Exactly one %s BWP per carrier must have ActiveInitial=true.", ...
            direction);
    end
    if numel(unique(ids(members))) ~= numel(members)
        error("sixgr:phy:frame:DuplicateBWPIdentity", ...
            "Configured %s BWP IDs must be unique within a carrier.", direction);
    end
end

activeDLID = ids(find(directions == "DL" & active, 1));
bwps = repmat(localEmptyBWPConfig(), numel(items), 1);
for itemIndex = 1:numel(items)
    item = items(itemIndex);
    direction = directions(itemIndex);
    if direction == "DL"
        grid = dlGrid;
    else
        grid = ulGrid;
    end
    commonSCS = localFirstField(item, ...
        ["CommonTDDReferenceSCSKHz", ...
        "common_tdd_reference_scs_khz"], commonTDDReferenceSCS);
    bwpID = ids(itemIndex);
    controlID = localNonnegativeIdentifier(localFirstField(item, ...
        ["ControlBWPID", "control_bwp_id"], activeDLID), ...
        "ControlBWPID");
    dataID = localNonnegativeIdentifier(localFirstField(item, ...
        ["DataBWPID", "data_bwp_id"], bwpID), "DataBWPID");
    bwps(itemIndex) = struct( ...
        "BWPID", bwpID, ...
        "Direction", direction, ...
        "CCID", ccid, ...
        "ServingCellID", servingCellID, ...
        "FrequencyRange", frequencyRange, ...
        "SCSKHz", localPositiveFinite(localFirstField(item, [ ...
            "SCSKHz", "SubcarrierSpacingKHz", ...
            "SubcarrierSpacing_kHz", "scs_khz"], ...
            grid.SubcarrierSpacingKHz), "BWP SCSKHz"), ...
        "CyclicPrefix", string(localFirstField(item, ...
            ["CyclicPrefix", "cyclic_prefix", "cp_type"], ...
            grid.CyclicPrefix)), ...
        "NStartBWP", localNonnegativeInteger(localFirstField(item, ...
            ["NStartBWP", "n_start_bwp"], grid.NStartGrid), ...
            "NStartBWP"), ...
        "NSizeBWP", localPositiveInteger(localFirstField(item, ...
            ["NSizeBWP", "n_size_bwp"], grid.NSizeGrid), ...
            "NSizeBWP"), ...
        "ControlConfigRef", string(localFirstField(item, ...
            ["ControlConfigRef", "control_config_ref"], ...
            lower(direction) + "_control_bwp_" + string(controlID))), ...
        "DataConfigRef", string(localFirstField(item, ...
            ["DataConfigRef", "data_config_ref"], ...
            lower(direction) + "_data_bwp_" + string(dataID))), ...
        "ControlBWPID", controlID, ...
        "DataBWPID", dataID, ...
        "ActiveInitial", active(itemIndex), ...
        "SwitchActivationTime", localActivationTime(item), ...
        "StateVersion", localNonnegativeInteger(localFirstField(item, ...
            ["StateVersion", "state_version", "Epoch", "epoch"], 0), ...
            "StateVersion"), ...
        "CommonTDDReferenceSCSKHz", double(commonSCS));
end
end

function time = localActivationTime(item)
raw = localFirstField(item, [ ...
    "SwitchActivationTime", "switch_activation_time", ...
    "SwitchActivationTick", "switch_activation_tick"], 0);
if isa(raw, "sixgr.phy.frame.AbsoluteTime")
    time = raw;
else
    time = sixgr.phy.frame.AbsoluteTime.fromTicks( ...
        localNonnegativeInteger(raw, "SwitchActivationTick"));
end
end

function snapshot = localCarrierSnapshot(carrier, bwps)
raw = carrier.toStruct();
bwpSnapshotCells = cell(numel(bwps), 1);
for index = 1:numel(bwps)
    bwpSnapshotCells{index} = localBWPSnapshot(bwps{index});
end
bwpSnapshots = vertcat(bwpSnapshotCells{:});
snapshot = localEmptyCarrierSnapshot();
snapshot.CCID = localNumericIdentifier(raw.CCID, "CCID");
snapshot.ServingCellID = localNumericIdentifier( ...
    raw.ServingCellID, "ServingCellID");
snapshot.SchedulingCCIDs = localNumericIdentifierVector( ...
    raw.SchedulingCCIDs, "SchedulingCCIDs");
snapshot.CenterFrequencyHz = raw.CenterFrequencyHz;
snapshot.DLCenterFrequencyHz = raw.DLCenterFrequencyHz;
snapshot.ULCenterFrequencyHz = raw.ULCenterFrequencyHz;
snapshot.Band = string(raw.Band);
snapshot.FrequencyRange = string(raw.FrequencyRange);
snapshot.ChannelBandwidthMHz = raw.ChannelBandwidthMHz;
snapshot.DuplexMode = string(raw.DuplexMode);
snapshot.DLCarrierGrid = raw.DLCarrierGrid;
snapshot.ULCarrierGrid = raw.ULCarrierGrid;
snapshot.BWPs = bwpSnapshots;
snapshot.ActiveDLBWPID = localNumericIdentifier( ...
    raw.ActiveDLBWPID, "ActiveDLBWPID");
snapshot.ActiveULBWPID = localNumericIdentifier( ...
    raw.ActiveULBWPID, "ActiveULBWPID");
snapshot.CarrierIndicatorMap = localNumericIndicatorMap( ...
    raw.CarrierIndicatorMap);
snapshot.ResourceNamespace = string(raw.ResourceNamespace);
snapshot.WaveformNamespace = string(raw.WaveformNamespace);
snapshot.MeasurementNamespace = string(raw.MeasurementNamespace);
snapshot.HARQStateCount = raw.HARQStateCount;
snapshot.IndexConvention = "zero_based";
end

function snapshot = localBWPStateSnapshot(carrier, bwps)
snapshot = localEmptyBWPState();
snapshot.CCID = localNumericIdentifier(carrier.CCID, "CCID");
snapshot.ActiveDLBWPID = localNumericIdentifier( ...
    carrier.BWPState.ActiveDLBWPID, "ActiveDLBWPID");
snapshot.ActiveULBWPID = localNumericIdentifier( ...
    carrier.BWPState.ActiveULBWPID, "ActiveULBWPID");
snapshot.Epoch = double(carrier.BWPState.Epoch);
snapshot.CurrentTick = carrier.BWPState.CurrentTime.tickValue();
directions = string(cellfun(@(x) x.Direction, bwps, ...
    "UniformOutput", false));
ids = cellfun(@(x) localNumericIdentifier(x.BWPID, "BWPID"), bwps);
snapshot.ConfiguredDLBWPIDs = reshape(ids(directions == "DL"), 1, []);
snapshot.ConfiguredULBWPIDs = reshape(ids(directions == "UL"), 1, []);
snapshot.PendingCommands = localTableStruct( ...
    carrier.BWPState.pendingTable());
snapshot.History = localTableStruct(carrier.BWPState.historyTable());
snapshot.IndexConvention = "zero_based";
end

function output = localTableStruct(input)
if isempty(input) || height(input) == 0
    output = struct([]);
else
    output = table2struct(input);
end
end

function snapshot = localBWPSnapshot(bwp)
raw = bwp.toStruct();
snapshot = raw;
snapshot.BWPID = localNumericIdentifier(raw.BWPID, "BWPID");
snapshot.CCID = localNumericIdentifier(raw.CCID, "CCID");
snapshot.ServingCellID = localNumericIdentifier( ...
    raw.ServingCellID, "ServingCellID");
snapshot.ControlBWPID = localNumericIdentifier( ...
    raw.ControlBWPID, "ControlBWPID");
snapshot.DataBWPID = localNumericIdentifier(raw.DataBWPID, "DataBWPID");
snapshot.ResourceGridDimensions = bwp.resourceGridDimensions(1);
snapshot.IndexConvention = "zero_based";
end

function policy = localTimingPolicy(cfg, carriers, identity)
allowedK0 = localConfiguredIntegerVector(cfg, [ ...
    "phy.tddTiming.allowedK0", ...
    "phy.tddTiming.pdcchToPDSCHK0"]);
allowedK1 = localConfiguredIntegerVector(cfg, [ ...
    "phy.tddTiming.dlHARQFeedbackK1Candidates"]);
allowedK2 = localConfiguredIntegerVector(cfg, [ ...
    "phy.tddTiming.allowedK2", ...
    "phy.tddTiming.pdcchToPUSCHK2", ...
    "phy.tddTiming.ulGrantK2"]);
[dlMu, ulMu] = localActiveDataNumerologies(carriers, identity);
dlCapability = sixgr.phy.frame.TimingPolicyCatalog.capability1(dlMu);
ulCapability = sixgr.phy.frame.TimingPolicyCatalog.capability1(ulMu);
n1 = localOptionalNonnegative(cfg, ...
    ["phy.tddTiming.n1PDSCHProcessingTimeSymbols"]);
if ~isfinite(n1)
    n1 = dlCapability.PDSCHN1Symbols;
end
n2 = localOptionalNonnegative(cfg, ...
    ["phy.tddTiming.n2PUSCHPreparationTimeSymbols"]);
if ~isfinite(n2)
    n2 = ulCapability.PUSCHN2Symbols;
end
profile = string(localFirst(cfg, [ ...
    "phy.tddTiming.capabilityProfileID"], ""));
if strlength(strtrim(profile)) == 0
    if dlMu == ulMu
        profile = sixgr.phy.frame.TimingPolicyCatalog. ...
            CapabilityProfileBase + "-mu" + string(dlMu);
    else
        profile = sixgr.phy.frame.TimingPolicyCatalog. ...
            CapabilityProfileBase;
    end
end
policy = struct( ...
    "AllowedK0", allowedK0, ...
    "AllowedK1", allowedK1, ...
    "AllowedK2", allowedK2, ...
    "K0Rows", localTimingRowsOrEmpty("K0", allowedK0, ...
        "phy.tddTiming.pdcchToPDSCHK0"), ...
    "K1Rows", localTimingRowsOrEmpty("K1", allowedK1, ...
        "phy.tddTiming.dlHARQFeedbackK1Candidates"), ...
    "K2Rows", localTimingRowsOrEmpty("K2", allowedK2, ...
        "phy.tddTiming.pdcchToPUSCHK2|phy.tddTiming.ulGrantK2"), ...
    "N1PDSCHProcessingTimeSymbols", n1, ...
    "N2PUSCHPreparationTimeSymbols", n2, ...
    "CapabilityProfileID", profile, ...
    "PolicyID", "attached_runtime_timing_policy", ...
    "Source", "resolved_internal_config_plus_pinned_3gpp_catalog", ...
    "StandardRelease", ...
        sixgr.phy.frame.TimingPolicyCatalog.StandardRelease, ...
    "SpecificationVersion", ...
