function [dlMu, ulMu] = localActiveDataNumerologies(carriers, identity)
scheduledIndex = find([carriers.CCID] == identity.ScheduledCCID, 1);
if isempty(scheduledIndex)
    error("sixgr:phy:frame:UnknownScheduledCarrier", ...
        "The timing policy scheduled carrier is not configured.");
end
bwps = carriers(scheduledIndex).BWPs;
dlMatch = [bwps.BWPID] == identity.DLBWPID & ...
    upper(string({bwps.Direction})) == "DL";
ulMatch = [bwps.BWPID] == identity.ULBWPID & ...
    upper(string({bwps.Direction})) == "UL";
if nnz(dlMatch) ~= 1 || nnz(ulMatch) ~= 1
    error("sixgr:phy:frame:UnknownDefaultTimingBWP", ...
        "The default DL/UL timing BWP identity is not configured exactly once.");
end
dlMu = double(bwps(dlMatch).Mu);
ulMu = double(bwps(ulMatch).Mu);
end

function identity = localDefaultIdentity(cfg, carriers)
schedulingCCID = localNonnegativeIdentifier(localFirst(cfg, [ ...
    "phy.frame.defaultIdentity.SchedulingCCID"], carriers(1).CCID), ...
    "SchedulingCCID");
carrierIndex = find([carriers.CCID] == schedulingCCID, 1);
if isempty(carrierIndex)
    error("sixgr:phy:frame:UnknownDefaultSchedulingCarrier", ...
        "Default scheduling carrier %d is not configured.", schedulingCCID);
end
carrier = carriers(carrierIndex);
indicator = localNonnegativeInteger(localFirst(cfg, [ ...
    "phy.frame.defaultIdentity.CarrierIndicator"], 0), ...
    "CarrierIndicator");
mapIndex = find([carrier.CarrierIndicatorMap.Indicator] == indicator, 1);
if isempty(mapIndex)
    error("sixgr:phy:frame:UnknownCarrierIndicator", ...
        "Default carrier indicator %d is not mapped by CC %d.", ...
        indicator, schedulingCCID);
end
scheduledCCID = carrier.CarrierIndicatorMap(mapIndex).ScheduledCCID;
scheduledIndex = find([carriers.CCID] == scheduledCCID, 1);
if isempty(scheduledIndex)
    error("sixgr:phy:frame:UnknownScheduledCarrier", ...
        "Default carrier indicator targets unconfigured CC %d.", scheduledCCID);
end
scheduled = carriers(scheduledIndex);
sourceBWPID = localNonnegativeIdentifier(localFirst(cfg, [ ...
    "phy.frame.defaultIdentity.SourceBWPID"], ...
    carrier.ActiveDLBWPID), "SourceBWPID");
identity = struct( ...
    "SchedulingCCID", schedulingCCID, ...
    "ScheduledCCID", scheduledCCID, ...
    "CarrierIndicator", indicator, ...
    "SourceBWPID", sourceBWPID, ...
    "DLBWPID", scheduled.ActiveDLBWPID, ...
    "ULBWPID", scheduled.ActiveULBWPID, ...
    "IndexConvention", "zero_based");
end

function localValidateCrossCarrierMaps(carriers)
configured = [carriers.CCID];
if numel(unique(configured)) ~= numel(configured)
    error("sixgr:phy:frame:DuplicateComponentCarrierIdentity", ...
        "Production component-carrier CCIDs must be unique.");
end
for carrierIndex = 1:numel(carriers)
    map = carriers(carrierIndex).CarrierIndicatorMap;
    targets = [map.ScheduledCCID];
    if any(~ismember(targets, configured))
        error("sixgr:phy:frame:UnknownScheduledCarrier", ...
            "Carrier %d maps an indicator to an unconfigured scheduled CC.", ...
            carriers(carrierIndex).CCID);
    end
end
end

