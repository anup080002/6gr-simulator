function output = localConcatenateSequences(first, second)
a = localStructSequence(first, "BWP configuration");
b = localStructSequence(second, "BWP configuration");
if isempty(a)
    output = b;
elseif isempty(b)
    output = a;
else
    fields = unique([string(fieldnames(a)); string(fieldnames(b))], "stable");
    a = localAddMissingFields(a, fields);
    b = localAddMissingFields(b, fields);
    output = [a(:); b(:)];
end
end

function output = localStructSequence(input, label)
if isempty(input)
    output = struct([]);
elseif iscell(input)
    if ~all(cellfun(@(x) isstruct(x) && isscalar(x), input(:)))
        error("sixgr:phy:frame:InvalidRuntimeStateSequence", ...
            "%s cells must contain scalar structs.", label);
    end
    output = input{1};
    for index = 2:numel(input)
        output = localConcatenateStruct(output, input{index});
    end
elseif isstruct(input)
    output = input(:);
else
    error("sixgr:phy:frame:InvalidRuntimeStateSequence", ...
        "%s must be a struct array or cell array of structs.", label);
end
end

function output = localConcatenateStruct(first, second)
fields = unique([string(fieldnames(first)); string(fieldnames(second))], ...
    "stable");
first = localAddMissingFields(first, fields);
second = localAddMissingFields(second, fields);
output = [first(:); second(:)];
end

function output = localUnionStruct(template, value)
if isempty(template)
    output = value;
    return;
end
fields = unique([string(fieldnames(template)); string(fieldnames(value))], ...
    "stable");
template = localAddMissingFields(template, fields);
value = localAddMissingFields(value, fields);
output = value;
for field = fields(:).'
    output.(char(field)) = value.(char(field));
end
end

function input = localAddMissingFields(input, fields)
for field = fields(:).'
    if ~isfield(input, char(field))
        [input.(char(field))] = deal([]);
    end
end
input = orderfields(input, cellstr(fields));
end

function value = localFirst(cfg, paths, defaultValue)
[value, found] = localFind(cfg, paths);
if ~found
    value = defaultValue;
end
end

function [value, found] = localFind(cfg, paths)
found = false;
value = [];
sentinel = struct("Missing", true);
for path = string(paths(:)).'
    candidate = sixgr.util.structGet(cfg, path, sentinel);
    if ~(isstruct(candidate) && isscalar(candidate) && ...
            isfield(candidate, "Missing") && candidate.Missing)
        value = candidate;
        found = true;
        return;
    end
end
end

function value = localFirstField(input, aliases, defaultValue)
value = defaultValue;
if ~isstruct(input) || ~isscalar(input)
    return;
end
names = string(fieldnames(input));
for alias = string(aliases(:)).'
    index = find(strcmpi(names, alias), 1);
    if ~isempty(index)
        candidate = input.(char(names(index)));
        if ~isempty(candidate)
            value = candidate;
        end
        return;
    end
end
end

function tf = localHasAnyField(input, aliases)
tf = false;
if ~isstruct(input) || ~isscalar(input)
    return;
end
names = string(fieldnames(input));
for alias = string(aliases(:)).'
    if any(strcmpi(names, alias))
        tf = true;
        return;
    end
end
end

