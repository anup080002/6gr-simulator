function snapshot=capturePDSCHChannelEstimate(rx)
% Actual pilot estimates and receiver operations, retained after decoding.
% No transmitted payload, physical reference H, or gain/phase fit is used.
required={'EffectiveLayerChannelEstimate','DMRSIndices','DMRSSymbols','Carrier','PDSCH', ...
    'ReceiverChannelOperator','OFDMInfo'};
assert(isstruct(rx) && all(isfield(rx,required)), ...
    'sixgr:phy:dl:IncompleteChannelEstimateCapture','Retain the executed PDSCH estimator inputs and receive operations.');
h=rx.EffectiveLayerChannelEstimate; indices=double(rx.DMRSIndices(:)); symbols=rx.DMRSSymbols(:);
shape=[size(h,1) size(h,2) size(h,3) size(h,4)];
assert(shape(1)==12*rx.Carrier.NSizeGrid && shape(2)==rx.Carrier.SymbolsPerSlot && ...
    shape(4)==rx.PDSCH.NumLayers && numel(indices)==numel(symbols) && ...
    ~isempty(indices) && all(isfinite(indices) & indices==fix(indices) & indices>=1 & ...
    indices<=prod(shape([1 2 4]))) && numel(unique(indices))==numel(indices) && ...
    all(isfinite(symbols)) && all(abs(symbols)>0), ...
    'sixgr:phy:dl:ChannelCaptureDomainMismatch','Do not substitute physical-port indices for effective DMRS-layer estimates.');
[k,l,p]=ind2sub(shape([1 2 4]),indices);
values=complex(zeros(numel(k),shape(3),'like',h));
for r=1:shape(3)
    values(:,r)=h(sub2ind(shape,k,l,repmat(r,size(k)),p));
end
assert(all(isfinite(values),'all'), ...
    'sixgr:phy:dl:IncompleteChannelEstimateCapture','Do not discard invalid channel samples.');
snapshot=struct('Contract',"PDSCH_pilot_channel_capture/v1", ...
    'GridShape',shape,'PilotIndices',indices,'PilotSymbols',symbols, ...
    'PilotChannelValues',values,'Carrier',rx.Carrier, ...
    'ReceiverOFDMInfo',rx.OFDMInfo,'ReceiverChannelOperator',rx.ReceiverChannelOperator, ...
    'Source',"actual_PDSCH_receiver_channel_estimator_inputs", ...
    'Domain',"effective_layer_channel",'ReferenceUsedByReceiver',false);
end
