function out=measurePDSCHPrecodePower(layerSym,portSym,prec,trace,bundle)
%MEASUREPDSCHPRECODEPOWER Audit the already-applied data-symbol mapping.
% X=S*W.' is a nonconjugating transpose. No matrix, symbol or scaler changes.
% unit_frobenius constrains trace(W'*W), NOT individual column powers or
% orthogonality. Equal-power orthogonal references below are descriptive for
% that convention, not additional requirements on valid explicit matrices.
if nargin<4, trace=[]; end
if nargin<5, bundle=[]; end
id='sixgr:phy:dl:PDSCHPrecodePowerAuthority';
assert(isstruct(prec)&&isscalar(prec)&&all(isfield(prec, ...
    {'MatrixPorts','NormalizationConvention','NormalizeW','NumLayers','NumPorts'})),id, ...
    'Retain the resolved actual matrix and declared normalization.');
S=double(layerSym); X=double(portSym); W=double(prec.MatrixPorts);
assert(isnumeric(layerSym)&&isnumeric(portSym)&&ismatrix(S)&&ismatrix(X)&& ...
    ~isempty(S)&&all(isfinite(S),'all')&&all(isfinite(X),'all')&& ...
    size(S,1)==size(X,1)&&size(S,2)==prec.NumLayers&&size(X,2)==prec.NumPorts&& ...
    isnumeric(prec.MatrixPorts)&&isequal(size(W),[prec.NumPorts prec.NumLayers])&& ...
    all(isfinite(W),'all'),id,'Retain finite original layer/port symbols and exact dimensions.');
convention=string(prec.NormalizationConvention); rank=size(S,2);
assert(isscalar(convention)&&any(convention== ...
    ["unit_frobenius","semi_unitary","explicit_no_normalization"]),id, ...
    'Use the resolved normalization convention, not an ambient default.');
if ~isempty(trace)
    assert(istable(trace)&&height(trace)==size(S,1)&&all(ismember( ...
        {'ResourceIndex','PRB','Symbol','PRG','SymbolGroup','Domain','Operation', ...
        'ResolvedMatrixDigest','AppliedMatrixDigest'},trace.Properties.VariableNames))&& ...
        isequal(double(trace.ResourceIndex),(0:size(S,1)-1).')&& ...
        all(string(trace.Domain)=="data")&&all(string(trace.Operation)=="apply"),id, ...
        'Use the original ordered canonical data-mapping trace.');
end
if isempty(bundle)
    assert(double(sixgr.util.structGet(prec,'NumPRG',1))==1&& ...
        isequaln(double(sixgr.util.structGet(prec,'MatrixPortsPerPRG',W)),W),id, ...
        'The legacy three-input route is only for one explicit matrix.');
    pages=reshape(W,size(W,1),rank,1); selection=ones(size(S,1),1);
    matrixDigests=sixgr.phy.mimo.MatrixContract.digest(W);
    source="single_explicit_resolved_matrix";
    if ~isempty(trace)
        assert(isequaln(W,eye(rank))&&all(double(trace.PRG)==0)&& ...
            all(double(trace.SymbolGroup)==0)&& ...
            all(string(trace.ResolvedMatrixDigest)=="identity_rank_"+string(rank))&& ...
            all(string(trace.AppliedMatrixDigest)=="identity_rank_"+string(rank)),id, ...
            'Without a bundle, retain the actual canonical identity-mapping receipt.');
        source="original_canonical_identity_mapping_trace";
    end
else
    assert(isa(bundle,'sixgr.pdsch.PDSCHPrecoderBundle')&&isscalar(bundle)&& ...
        bundle.NormalizationConvention==convention&&bundle.NLayerPorts==rank&& ...
        bundle.NPhysicalTxAntennas==size(X,2)&&isequaln(double(bundle.W(:,:,1,1)),W),id, ...
        'The actual bundle must agree with resolved matrix dimensions and convention.');
    assert(~isempty(trace),id,'The actual bundle requires its original data-mapping trace.');
    if isfield(prec,'NumPRG')
        assert(isequal(double(prec.NumPRG),bundle.NPRG),id, ...
            'The resolved PRG count must match the actual bundle.');
    end
    selection=zeros(size(S,1),1);
    % Resolve once per distinct original physical resource coordinate, not
    % from row ordinals or a first-page assumption. No precoder application.
    [coordinates,~,groups]=unique([double(trace.PRB) double(trace.Symbol)],'rows');
    for q=1:size(coordinates,1)
        [~,prg,symbolGroup,digest]=bundle.slice(coordinates(q,1),coordinates(q,2));
        use=groups==q;
        assert(all(double(trace.PRG(use))==prg)&& ...
            all(double(trace.SymbolGroup(use))==symbolGroup)&& ...
            all(string(trace.ResolvedMatrixDigest(use))==digest)&& ...
            all(string(trace.AppliedMatrixDigest(use))==digest),id, ...
            'Actual resource-to-page selection and both producer digests must agree.');
        selection(use)=sub2ind([bundle.NPRG bundle.NSymbolGroups],prg+1,symbolGroup+1);
    end
    pages=reshape(double(bundle.W),size(X,2),rank,[]);
    if isfield(prec,'MatrixPortsPerPRG')
        assert(isequaln(double(prec.MatrixPortsPerPRG),pages),id, ...
            'The complete resolved page population must match the actual bundle.');
    end
    matrixDigests=strings(size(pages,3),1);
    for q=1:size(pages,3), matrixDigests(q)=sixgr.phy.mimo.MatrixContract.digest(pages(:,:,q)); end
    source="original_canonical_data_precoder_trace_and_immutable_bundle";
end
n=size(pages,3); grams=complex(zeros(rank,rank,n)); norms=zeros(rank,n); powers=zeros(n,1);
expectedEnergy=0; symbolError=0; pageEnergy=zeros(n,1); pageObserved=zeros(n,1); counts=zeros(n,1);
for q=1:n
    page=pages(:,:,q); grams(:,:,q)=page'*page;
    norms(:,q)=sqrt(sum(abs(page).^2,1)).'; powers(q)=sum(abs(page).^2,'all');
    use=selection==q; counts(q)=nnz(use);
    if ~any(use), continue; end
    predicted=S(use,:)*page.';
    pageEnergy(q)=sum(abs(predicted).^2,'all'); pageObserved(q)=sum(abs(X(use,:)).^2,'all');
    expectedEnergy=expectedEnergy+pageEnergy(q);
    symbolError=max(symbolError,max(abs(X(use,:)-predicted),[],'all'));
end
% Preserve the original raw summaries (including their source precision).
layerEnergy=sum(abs(layerSym(:)).^2); portEnergy=sum(abs(portSym(:)).^2);
observedEnergy=sum(abs(X).^2,'all'); delta=observedEnergy-expectedEnergy;
target=NaN; expectedGram=NaN(rank); expectedNorms=NaN(rank,1);
requiredGram=convention=="semi_unitary";
if requiredGram, target=rank; expectedGram=eye(rank); expectedNorms=ones(rank,1);
elseif convention=="unit_frobenius", target=1;
end
gramError=NaN; columnError=NaN; traceError=NaN;
if requiredGram
    gramError=max(abs(grams-expectedGram),[],'all');
    columnError=max(abs(norms-expectedNorms),[],'all');
end
if isfinite(target), traceError=max(abs(powers-target)); end
referenceGram=NaN(rank); referenceNorms=NaN(rank,1); referenceGramError=NaN; referenceColumnError=NaN;
if isfinite(target)
    referenceGram=eye(rank)*(target/rank); referenceNorms=repmat(sqrt(target/rank),rank,1);
    referenceGramError=max(abs(grams-referenceGram),[],'all');
    referenceColumnError=max(abs(norms-referenceNorms),[],'all');
end
out=struct('ContractVersion',"PDSCHPrecodePower/v2", ...
    'NormalizeW',logical(prec.NormalizeW),'NumLayers',double(prec.NumLayers),'NumPorts',double(prec.NumPorts), ...
    'NormalizationConvention',convention,'NormalizationAuthority',"resolved_actual_precoder_not_ambient_config", ...
    'ColumnNorms',norms(:,1).','ColumnNormsPerPage',norms,'GramPerPage',grams, ...
    'ExpectedColumnNorms',expectedNorms.','ExpectedGram',expectedGram, ...
    'ColumnNormConstraintApplicable',requiredGram,'GramConstraintApplicable',requiredGram, ...
    'ColumnNormMaxError',columnError,'OrthonormalColumnMaxError',gramError, ...
    'FrobeniusPowerPerPage',powers,'ExpectedFrobeniusPower',target,'NormalizationTraceMaxError',traceError, ...
    'EqualPowerOrthogonalReferenceGram',referenceGram, ...
    'EqualPowerOrthogonalReferenceColumnNorms',referenceNorms.', ...
    'EqualPowerOrthogonalReferenceGramMaxDeviation',referenceGramError, ...
    'EqualPowerOrthogonalReferenceColumnMaxDeviation',referenceColumnError, ...
    'EqualPowerOrthogonalReferenceRequired',requiredGram, ...
    'LayerTotalEnergy',double(layerEnergy),'PortTotalEnergy',double(portEnergy), ...
    'TotalEnergyDelta',double(portEnergy-layerEnergy), ...
    'ExpectedMappedPortEnergy',expectedEnergy,'MappedPortEnergyDouble',observedEnergy, ...
    'MappedEnergyDelta',delta,'TotalPowerMaxAbsError',abs(delta), ...
    'TotalPowerRelativeError',abs(delta)/max(expectedEnergy,realmin), ...
    'MappedSymbolMaxAbsError',symbolError,'ExpectedMappedPortEnergyPerPage',pageEnergy, ...
    'ObservedPortEnergyPerPage',pageObserved,'MappedResourceCountPerPage',counts, ...
    'MatrixSHA256PerPage',matrixDigests,'MappingEvidenceSource',source, ...
    'Equation',"X_equals_S_times_W_transpose", ...
    'EnergyErrorDefinition',"actual_port_energy_minus_energy_of_original_S_times_actual_W_transpose", ...
    'MatrixRescaled',false,'WaveformPowerQualification',false);
end
