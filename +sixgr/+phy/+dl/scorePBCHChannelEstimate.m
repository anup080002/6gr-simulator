function score=scorePBCHChannelEstimate(pbch,independentReference)
% Post-reception error scoring; never an input to synchronization/decoding.
% The caller must derive the reference from the actually applied channel,
% TX projection/power and the receiver's FFT window. Do not estimate a
% reference by fitting the received pilots or aligning gain/phase to Hest.
assert(isstruct(pbch) && isscalar(pbch) && ...
    isequal(sixgr.util.structGet(pbch,'ChannelEstimateAvailable',false),true), ...
    'sixgr:phy:pbch:MissingChannelEstimateForScoring', ...
    'An actual PBCH receiver channel estimate is required.');
estimate=pbch.ChannelEstimateGrid;
assert(size(estimate,1)==240 && size(estimate,2)==4 && size(estimate,4)==1, ...
    'sixgr:phy:pbch:ChannelScoringGridShape', ...
    'Score the 240-by-4 SSB grid, every RX branch and its single logical PBCH port.');
validateattributes(pbch.NCellID,{'numeric'},{'scalar','integer','>=',0,'<=',1007});
indices=nrPBCHDMRSIndices(double(pbch.NCellID));
raw=sixgr.phy.srs.pilotChannelNMSE(estimate,independentReference,indices);
score=struct('NMSE_dB',raw.dB,'NMSELinear',raw.Linear, ...
    'NMSEScoringAvailable',raw.Available, ...
    'ChannelNMSEComparedComplexValues',raw.ComparedComplexValueCount, ...
    'ChannelNMSEErrorEnergy',raw.ErrorEnergy, ...
    'ChannelNMSEReferenceEnergy',raw.ReferenceEnergy, ...
    'ChannelNMSEPilotResourceCount',raw.PilotResourceCount, ...
    'ChannelNMSENumReceiveBranches',raw.NumReceiveAntennas, ...
    'ChannelNMSENumLogicalPorts',raw.NumSRSPorts, ...
    'ChannelNMSEPerReceiveBranchLinear',raw.PerReceiveAntennaPortLinear, ...
    'ChannelNMSEReferencePlane',"PBCH_DMRS_effective_channel_on_receiver_SSB_FFT_grid", ...
    'ChannelNMSEGainOrPhaseFitted',false, ...
    'ChannelNMSEMissingValuesDiscarded',false, ...
    'ChannelNMSEReferenceUsedByReceiver',false);
end
