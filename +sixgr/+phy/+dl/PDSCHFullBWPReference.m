classdef PDSCHFullBWPReference
    %PDSCHFULLBWPREFERENCE TX-owned, declared full-BWP PDSCH power model.
    % Q=I is a SIMULATION reference definition, not measured layer covariance
    % or a normative pre-RF equation. The reference contains no RS/SSB. Actual
    % RS, boosts, reserved REs and auxiliary signals stay in the numerator.
    % No samples, grids, synthesized payload or counterfactual waveform are
    % stored/generated here. Immutable original mapping identities are used.
    properties (SetAccess=immutable)
        Receipt (1,1) struct
        SourceBinding (1,1) struct
        OFDMContract (1,1) struct
    end
    methods (Static)
        function obj=build(tx,bwp)
            % BWPStartCarrierRelative is explicitly carrier-relative. The
            % caller converts native NStartBWP (CRB origin) exactly once.
            assert(isstruct(tx) && isscalar(tx) && isstruct(bwp) && isscalar(bwp), ...
                'sixgr:rf:PDSCHPowerReferenceAuthority','Original TX and BWP context are required.');
            assert(all(isfield(bwp,{'StartCarrierRelative','NumPRB','Authority'})) && ...
                isscalar(string(bwp.Authority)) && ~ismissing(string(bwp.Authority)) && ...
                strlength(string(bwp.Authority))>0, ...
                'sixgr:rf:PDSCHPowerReferenceBWP','BWP reference needs explicit geometry and authority provenance.');
            a=tx.Assignment; p=tx.ResourcePlan; c=tx.Carrier; o=tx.OFDMInfo;
            assert(isa(a,'sixgr.pdsch.PDSCHSchedulingAssignment') && ...
                isa(p,'sixgr.pdsch.PDSCHResourcePlan') && isa(c,'nrCarrierConfig'), ...
                'sixgr:rf:PDSCHPowerReferenceAuthority','Canonical original assignment/resource/carrier are required.');
            start=localInteger(bwp.StartCarrierRelative,0); count=localInteger(bwp.NumPRB,1);
            nrb=double(c.NSizeGrid); K=12*nrb; L=double(c.SymbolsPerSlot);
            assert(start+count<=nrb && ...
                isequal(double(a.get('PRBSetCarrierRelative')),double(p.PRBSet)) && ...
                all(p.PRBSet>=start & p.PRBSet<start+count), ...
                'sixgr:rf:PDSCHPowerReferenceBWP','Original PDSCH allocation must lie inside its declared BWP.');
            assert(isequal(double(a.get('PRBSetBWPRelative'))+start,double(p.PRBSet)), ...
                'sixgr:rf:PDSCHPowerReferenceBWP','Original BWP-relative and carrier-relative allocation disagree.');
            assert(size(tx.Grid,1)==K && size(tx.Grid,2)==L && ...
                size(tx.Grid,3)==size(tx.Waveform,2), ...
                'sixgr:rf:PDSCHPowerReferenceAuthority','Original grid and waveform dimensions disagree.');
            active=find(reshape(sum(abs(double(tx.Grid)).^2,[1 3]),[],1)>0).'-1;
            assert(~isempty(active) && all(isfinite(tx.Grid),'all'), ...
                'sixgr:rf:PDSCHPowerReferenceAuthority','Original composite grid must be finite and nonempty.');
            ofdm=localOFDM(o,c);
            source=struct('AssignmentId',a.AssignmentId, ...
                'AssignmentValidationDigest',a.validateForExecution(), ...
                'ConfigurationEpoch',double(a.get('ConfigurationEpoch')), ...
                'PRBSetCarrierRelative',double(p.PRBSet), ...
                'SymbolAllocation',double(p.SymbolAllocation), ...
                'ReferenceConfigurationDigest',p.ReferenceConfigurationDigest, ...
                'BWPStartCarrierRelative',start,'BWPNumPRB',count,'BWPAuthority',string(bwp.Authority), ...
                'CarrierStartCRB',double(c.NStartGrid),'CarrierNumPRB',nrb, ...
                'AssignmentAbsoluteSlot',double(a.get('PDSCHAbsoluteSlot')), ...
                'CarrierNFrame',double(c.NFrame),'CarrierNSlot',double(c.NSlot), ...
                'GridSHA256',string(o.GridSHA256),'WaveformSHA256',string(o.WaveformSHA256), ...
                'GridSize',[K L size(tx.Grid,3)],'WaveformSize',double(size(tx.Waveform)), ...
                'PrecoderBundleDigest',"",'MatrixDigestPerSlice',strings(0), ...
                'PrecoderNormalizationConvention',"explicit_identity");
            [energyPerSymbol,mappingSource,status,source]=localMapping(tx,start,count,active,source);
            supported=status=="available";
            if ~ofdm.NativeUnwindowed
                supported=false; status="unsupported_windowed_or_resampled_OFDM_reference";
            elseif ~isequal(ofdm.CyclicPrefixLengths(1:L),ofdm.CurrentSlotCyclicPrefixLengths)
                % The common scaler currently consumes the leading CP list.
                % Do not claim its active-sample plane for a shifted CP list.
                supported=false; status="unsupported_shifted_CP_scaler_reference";
            end
            E=sum(energyPerSymbol);
            referencePower=E/(numel(active)*ofdm.Nfft^2);
            if ~supported, referencePower=NaN; end
            receipt=struct('ContractVersion',"PDSCHFullBWPReference/v1", ...
                'Available',supported,'Status',status, ...
                'Definition',"full_configured_BWP_PDSCH_no_RS_unit_energy_uncorrelated_layers", ...
                'ReferenceClass',"declared_simulation_covariance_not_measured", ...
                'NormativeEquation',false,'MeasuredReference',false, ...
                'AcceptedFeedPowerClaim',false,'RadiatedPowerClaim',false, ...
                'LayerCovarianceDefinition',"identity_Q_equals_I", ...
                'NumLayers',double(tx.NumLayers),'MappingSource',mappingSource, ...
                'BWPStartCarrierRelative',start,'BWPNumPRB',count,'BWPAuthority',string(bwp.Authority), ...
                'ReferenceActiveSymbolsZeroBased',active, ...
                'ExpectedGridEnergyPerSymbol',energyPerSymbol, ...
                'ExpectedFullBWPGridEnergy',E, ...
                'ExpectedUsefulSamplePower_native_squared',referencePower, ...
                'TransformDefinition',"native_ifft_1_over_Nfft_unwindowed_no_resampling", ...
                'ReferencePlane',"original_PDSCH_output_columns_pre_power_context_pre_RF", ...
                'PilotAndAuxiliaryEnergyTreatment',"actual_composite_numerator_only", ...
                'ActualNumeratorScope',"entire_original_carrier_grid_all_output_columns_on_actual_active_symbols_including_auxiliary_outside_reference_BWP", ...
                'SourceBinding',source,'OFDMContract',ofdm);
            receipt.ReceiptSHA256=string(sixgr.util.sha256Hex(jsonencode(receipt)));
            obj=sixgr.phy.dl.PDSCHFullBWPReference(receipt,source,ofdm);
        end
    end
    methods
        function [referencePower,receipt]=validate(obj,x,info,grid,activeSymbols)
            assert(isscalar(obj) && isstruct(info) && isscalar(info) && ...
                isfield(info,'PDSCHPowerReferenceBinding') && ...
                isequaln(info.PDSCHPowerReferenceBinding,obj.SourceBinding), ...
                'sixgr:rf:PDSCHPowerReferenceAuthority','Power reference must retain its original TX binding.');
            s=obj.SourceBinding; o=obj.OFDMContract;
            assert(isequal(localOFDM(info.OFDM,[]),o) && ...
                isfield(info,'ResourcePlan') && isa(info.ResourcePlan,'sixgr.pdsch.PDSCHResourcePlan') && ...
                isequal(double(info.ResourcePlan.PRBSet),s.PRBSetCarrierRelative) && ...
                isequal(double(info.ResourcePlan.SymbolAllocation),s.SymbolAllocation) && ...
                info.ResourcePlan.ReferenceConfigurationDigest==s.ReferenceConfigurationDigest, ...
                'sixgr:rf:PDSCHPowerReferenceAuthority','Original OFDM/resource-plan binding changed.');
            assert(isequal([size(grid,1) size(grid,2) size(grid,3)],s.GridSize) && ...
                isequal(double(size(x)),s.WaveformSize) && ...
                string(sixgr.phy.waveform.WaveformHash.numeric(grid))==s.GridSHA256 && ...
                string(sixgr.phy.waveform.WaveformHash.numeric(x))==s.WaveformSHA256 && ...
                string(info.OFDM.GridSHA256)==s.GridSHA256 && ...
                string(info.OFDM.WaveformSHA256)==s.WaveformSHA256, ...
                'sixgr:rf:PDSCHPowerReferenceAuthority','Original waveform/grid bytes do not match the TX reference.');
            assert(obj.Receipt.Available,'sixgr:rf:PDSCHPowerReferenceUnsupported', ...
                'Fixed-EPRE PDSCH reference is unavailable: %s.',obj.Receipt.Status);
            assert(isequal(double(activeSymbols(:).'-1),obj.Receipt.ReferenceActiveSymbolsZeroBased), ...
                'sixgr:rf:PDSCHPowerReferenceAuthority','Measured useful-symbol support differs from original grid support.');
            referencePower=obj.Receipt.ExpectedUsefulSamplePower_native_squared;
            assert(isfinite(referencePower) && referencePower>0, ...
                'sixgr:rf:PDSCHPowerReferenceAuthority','Declared reference power must be finite and positive.');
            receipt=obj.Receipt;
        end
    end
    methods (Access=private)
        function obj=PDSCHFullBWPReference(receipt,source,ofdm)
            obj.Receipt=receipt; obj.SourceBinding=source; obj.OFDMContract=ofdm;
        end
    end
end

function value=localInteger(raw,minimum)
assert(isnumeric(raw) && isreal(raw) && isscalar(raw) && isfinite(raw) && ...
    raw==fix(raw) && raw>=minimum,'sixgr:rf:PDSCHPowerReferenceBWP', ...
    'BWP geometry must be exact finite integer scalars.');
value=double(raw);
end

function out=localOFDM(o,c)
required={'EngineUsed','Nfft','SampleRate','Windowing','CyclicPrefixLengths','OFDMSamplingResolution'};
assert(isstruct(o) && isscalar(o) && all(isfield(o,required)), ...
    'sixgr:rf:PDSCHPowerReferenceAuthority','Original canonical OFDM metadata is required.');
r=o.OFDMSamplingResolution;
assert(isstruct(r) && all(isfield(r,{'Nfft','SampleRate','CyclicPrefixLengthsPerSlot', ...
    'WindowingSamples','OccupiedBandwidthHz','NSizeGrid'})), ...
    'sixgr:rf:PDSCHPowerReferenceAuthority','Original applied OFDM sampling resolution is required.');
n=double(o.Nfft); fs=double(o.SampleRate); cp=double(o.CyclicPrefixLengths(:).');
assert(isscalar(n) && isfinite(n) && n>0 && n==fix(n) && ...
    isscalar(fs) && isfinite(fs) && fs>0 && ~isempty(cp) && all(isfinite(cp) & cp>=0 & cp==fix(cp)) && ...
    n==double(r.Nfft) && fs==double(r.SampleRate) && double(o.Windowing)==double(r.WindowingSamples), ...
    'sixgr:rf:PDSCHPowerReferenceAuthority','Contradictory native OFDM parameters.');
% The original resolver strictly binds Fs=Nfft*SCS. No measured noise gain
% is repurposed as a signal-transform coefficient.
scsHz=double(r.OccupiedBandwidthHz)/(12*double(r.NSizeGrid));
assert(isscalar(scsHz) && isfinite(scsHz) && scsHz>0, ...
    'sixgr:rf:PDSCHPowerReferenceAuthority','Original OFDM occupied-bandwidth/SCS metadata is invalid.');
native=string(o.EngineUsed)=="canonical_nrOFDMModulate" && double(o.Windowing)==0 && ...
    abs(fs-n*scsHz)<=max(1e-6,fs*1e-12);
if ~isempty(c)
    assert(abs(scsHz-double(c.SubcarrierSpacing)*1000)<1e-6 && r.NSizeGrid==c.NSizeGrid, ...
        'sixgr:rf:PDSCHPowerReferenceAuthority','Original carrier and OFDM occupied bandwidth disagree.');
end
out=struct('EngineUsed',string(o.EngineUsed),'Nfft',n,'SampleRateHz',fs, ...
    'SubcarrierSpacingHz',scsHz, ...
    'WindowingSamples',double(o.Windowing),'CyclicPrefixLengths',cp, ...
    'CurrentSlotCyclicPrefixLengths',double(r.CyclicPrefixLengthsPerSlot(:).'), ...
    'NativeUnwindowed',native);
end

function [energy,source,status,binding]=localMapping(tx,start,count,active,binding)
energy=NaN(size(active)); source=""; status="available";
b=tx.PrecoderBundle;
if isempty(b)
    assert(size(tx.Grid,3)==tx.NumLayers && ...
        string(tx.PrecoderMode)=="explicit_identity_no_bundle", ...
        'sixgr:rf:PDSCHPowerReferenceAuthority','Only the actual canonical identity path may omit its matrix bundle.');
    energy(:)=12*count*double(tx.NumLayers);
    source="original_explicit_identity_no_bundle"; return;
end
assert(isa(b,'sixgr.pdsch.PDSCHPrecoderBundle') && ...
    b.NLayerPorts==tx.NumLayers && b.NPhysicalTxAntennas<=size(tx.Grid,3), ...
    'sixgr:rf:PDSCHPowerReferenceAuthority','Original precoder bundle dimensions disagree.');
binding.PrecoderBundleDigest=b.ImmutableBundleDigest;
binding.MatrixDigestPerSlice=b.MatrixDigestPerSlice;
binding.PrecoderNormalizationConvention=b.NormalizationConvention;
t=tx.DataPrecoderTrace;
assert(istable(t) && all(ismember({'PRG','SymbolGroup','AppliedMatrixDigest','ResolvedMatrixDigest'},t.Properties.VariableNames)), ...
    'sixgr:rf:PDSCHPowerReferenceAuthority','Original applied matrix trace is required.');
assert(all(isfinite(t.PRG) & t.PRG==fix(t.PRG) & t.PRG>=0 & t.PRG<b.NPRG) && ...
    all(isfinite(t.SymbolGroup) & t.SymbolGroup==fix(t.SymbolGroup) & t.SymbolGroup>=0 & t.SymbolGroup<b.NSymbolGroups), ...
    'sixgr:rf:PDSCHPowerReferenceAuthority','Applied trace page indices are invalid.');
indices=sub2ind([b.NPRG b.NSymbolGroups],t.PRG+1,t.SymbolGroup+1);
digests=b.MatrixDigestPerSlice(indices);
assert(all(t.AppliedMatrixDigest==digests & t.ResolvedMatrixDigest==digests), ...
    'sixgr:rf:PDSCHPowerReferenceAuthority','Applied matrix identity differs from the original bundle.');
wide=(startsWith(b.Mode,"wideband") || b.Mode=="siso_identity") && ...
    b.NPRG==1 && b.NSymbolGroups==1;
if wide
    energy(:)=12*count*sum(abs(b.W(:,:,1,1)).^2,'all');
    source="original_static_wideband_mapping_declared_over_full_BWP";
else
    [hasPRB,prbIndex]=ismember(start+(0:count-1),b.PRBSet);
    [hasSymbol,symbolIndex]=ismember(active,b.ScheduledSymbols);
    if ~all(hasPRB) || ~all(hasSymbol)
        status="unsupported_selective_mapping_without_full_BWP_reference_coverage";
        source="original_selective_bundle_incomplete_reference_support"; return;
    end
    for j=1:numel(active)
        group=b.SymbolGroupIndexPerSymbol(symbolIndex(j))+1;
        E=0;
        for k=prbIndex
            page=b.PRGIndexPerPRB(k)+1;
            E=E+12*sum(abs(b.W(:,:,page,group)).^2,'all');
        end
        energy(j)=E;
    end
    source="original_selective_mapping_with_exact_full_BWP_reference_coverage";
end
assert(all(isfinite(energy) & energy>0),'sixgr:rf:PDSCHPowerReferenceAuthority', ...
    'Declared covariance reference must have positive finite mapped energy.');
end
