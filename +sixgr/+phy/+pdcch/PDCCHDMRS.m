classdef PDCCHDMRS
    %PDCCHDMRS Pure TS 38.211 PDCCH DM-RS sequence and RE coordinates.

    methods (Static)
        function result = generate(context)
            required = ["NumerologyMu","Slot","Symbol","NID","CORESETRBs", ...
                "PrecoderGranularity","AttemptedPRBs"];
            if ~(isstruct(context) && isscalar(context)) || ...
                    any(~isfield(context, cellstr(required)))
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "PDCCH DM-RS context is incomplete.");
            end
            mu = localInteger(context.NumerologyMu, 0, 4, "NumerologyMu");
            slot = localInteger(context.Slot, 0, 159, "Slot");
            symbol = localInteger(context.Symbol, 0, 13, "Symbol");
            nID = localInteger(context.NID, 0, 65535, "NID");
            nRB = localInteger(context.CORESETRBs, 1, 275, "CORESETRBs");
            attempted = double(context.AttemptedPRBs(:).');
            if isempty(attempted) || any(attempted < 0 | attempted >= nRB | attempted ~= fix(attempted))
                error("sixgr:phy:pdcch:invalid_coreset_frequency_resources", ...
                    "AttemptedPRBs must be unique zero-based PRBs within the CORESET.");
            end
            attempted = unique(attempted, "stable");
            cInit = mod(2^17 * (14*slot + symbol + 1) * (2*nID + 1) + 2*nID, 2^31);
            bits = sixgr.phy.pdcch.PDCCHScrambler.gold(cInit, 6*nRB);
            symbols = sixgr.phy.pdcch.PDCCHQPSK.modulate(bits);
            offsets = [1 5 9];
            mappedSymbols = complex(zeros(3*numel(attempted),1));
            mapped = strings(3*numel(attempted),1);
            cursor = 1;
            for prb = attempted
                seqIdx = 3*prb + (1:3);
                mappedSymbols(cursor:cursor+2) = symbols(seqIdx);
                for kk = 1:3
                    mapped(cursor+kk-1) = sprintf("%d:%d:%d", symbol, prb, offsets(kk));
                end
                cursor = cursor + 3;
            end
            bitText = char(join(string(bits.'), ""));
            indexText = char(join(mapped.', "|"));
            result = struct( ...
                "NumerologyMu", mu, ...
                "Slot", slot, ...
                "Symbol", symbol, ...
                "NID", nID, ...
                "CInit", double(cInit), ...
                "SequenceBits", bits, ...
                "SequenceSymbols", symbols, ...
                "SequenceLength", numel(symbols), ...
                "AttemptedPRBs", attempted, ...
                "DMRSSubcarrierOffsets", offsets, ...
                "MappedCoordinates", mapped, ...
                "MappedSymbols", mappedSymbols, ...
                "MappedRECount", numel(mapped), ...
                "SequenceBitsSHA256", string(sixgr.rrc.asn1.sha256Hex(uint8(unicode2native(bitText, "UTF-8")))), ...
                "SequenceSHA256", localComplexHash(symbols), ...
                "IndexSHA256", string(sixgr.rrc.asn1.sha256Hex(uint8(unicode2native(indexText, "UTF-8")))), ...
                "PrecoderGranularity", string(context.PrecoderGranularity), ...
                "Status", "PASS");
        end
    end
end

function value = localInteger(value, minimum, maximum, name)
value = double(value);
if ~(isscalar(value) && isfinite(value) && value >= minimum && value <= maximum && value == fix(value))
    error("sixgr:phy:pdcch:field_out_of_range", ...
        "%s must be an integer in [%d,%d].", name, minimum, maximum);
end
end

function value = localComplexHash(symbols)
payload = double([real(symbols(:)).'; imag(symbols(:)).']);
value = string(sixgr.rrc.asn1.sha256Hex(typecast(payload(:), "uint8")));
end
