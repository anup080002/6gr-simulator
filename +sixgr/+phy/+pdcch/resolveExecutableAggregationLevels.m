function [levels, evidence] = resolveExecutableAggregationLevels(cfg, configuredLevels)
%RESOLVEEXECUTABLEAGGREGATIONLEVELS Apply resolved SearchSpace authority.
%   Aggregation levels remain scenario policy, but an active PDCCH may only
%   select a level for which the bandwidth/duration-derived SearchSpace has
%   at least one candidate. This rule is duplex-neutral and applies to both
%   FDD and TDD control occasions.

allLevels = [1 2 4 8 16];
configuredLevels = unique(double(reshape(configuredLevels, 1, [])), "stable");
if isempty(configuredLevels) || any(~ismember(configuredLevels, allLevels))
    error("sixgr:phy:pdcch:invalid_aggregation_level", ...
        "Configured PDCCH aggregation levels must be drawn from 1/2/4/8/16.");
end

resolvedCandidates = double(sixgr.util.structGet(cfg, ...
    "phy.pdcch.searchSpace.numCandidates", []));
resolvedCandidates = reshape(resolvedCandidates, 1, []);
if isempty(resolvedCandidates)
    levels = configuredLevels;
    source = "configured_levels_no_resolved_search_space";
elseif numel(resolvedCandidates) ~= numel(allLevels) || ...
        any(~isfinite(resolvedCandidates) | resolvedCandidates < 0 | ...
        resolvedCandidates ~= fix(resolvedCandidates))
    error("sixgr:phy:pdcch:invalid_resolved_candidate_count", ...
        "Resolved PDCCH SearchSpace candidates must be five nonnegative " + ...
        "integers for aggregation levels 1/2/4/8/16.");
else
    levels = configuredLevels(ismember(configuredLevels, ...
        allLevels(resolvedCandidates > 0)));
    source = "configured_levels_bounded_by_resolved_search_space_candidates";
end

if isempty(levels)
    error("sixgr:phy:pdcch:no_executable_aggregation_level", ...
        "The active CORESET/SearchSpace has no candidate for any enabled " + ...
        "PDCCH aggregation level. Correct the YAML CORESET, enabled " + ...
        "aggregation levels, or search-space candidate configuration.");
end

evidence = struct( ...
    "ConfiguredLevels", configuredLevels, ...
    "ExecutableLevels", levels, ...
    "ResolvedCandidates", resolvedCandidates, ...
    "Source", char(source));
end
