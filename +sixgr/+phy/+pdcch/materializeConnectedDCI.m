function assignment = materializeConnectedDCI(rx, info, cfg)
% Receiver-owned semantic capsule; not yet a data execution authorization.
% No scheduler intention, TX object, TBS or expected payload is input.
assert(isstruct(rx) && isstruct(info) && isequal(rx.Ok,true) && rx.ErrFlag==0 && ...
    isequal(info.ReceiverConfiguredMonitoring,true) && ...
    string(rx.DCISelectionSource)=="receiver_installed_context_crc_and_semantic_parse", ...
    'sixgr:phy:pdcch:ConnectedReceptionRequired', ...
    'Materialization requires accepted receiver-owned blind monitoring.');
context=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,rx.DCIFormat);
d=context.Data;
assert(string(rx.DCIContextDigest)==context.Digest && info.RNTI==d.RNTIValue, ...
    'sixgr:phy:pdcch:stale_bwp_context', ...
    'Received identity/context must match the installed receiver state.');
decoded=sixgr.phy.pdcch.DCIParser.parse(rx.DCIBits,context);
assert(isequaln(decoded,rx.DecodedDCI), ...
    'sixgr:phy:pdcch:ReceivedSemanticMismatch', ...
    'Received semantic fields must agree with the actual CRC-accepted bits.');
f=decoded.Fields;
controlSlot=double(cfg.lls6g.runtime.AbsoluteSlotIndex0);
validateattributes(controlSlot,{'double'},{'scalar','integer','finite','nonnegative'});
assert(info.ReceiverAbsoluteSlotIndex0==controlSlot, ...
    'sixgr:phy:pdcch:ReceivedClockMismatch', ...
    'Materialization must retain the absolute slot used by the control receiver.');
if decoded.Direction=="DL", root=cfg.phy.pdsch; else, root=cfg.phy.pusch; end
profile=sixgr.phy.pdcch.resolveConnectedMCS(root,f.mcs);
assert(profile.Valid || profile.RequiresHARQHistory,'sixgr:phy:pdcch:field_out_of_range', ...
    'Received MCS must be valid in the installed directional MCS table.');
rank=numel(f.dmrs_port_set);
if decoded.Direction=="UL", rank=f.precoding_information_and_number_of_layers_rank_minus1+1; end
assert(rank==numel(f.dmrs_port_set),'sixgr:phy:pdcch:ReceivedSemanticMismatch', ...
    'DM-RS ports and received rank must agree.');
assignment=struct('Direction',decoded.Direction,'DCIFormat',decoded.Format, ...
    'RNTI',d.RNTIValue,'ConfigurationEpoch',d.ConfigurationEpoch, ...
    'ContextDigest',context.Digest,'PayloadHash',decoded.PayloadHash, ...
    'ControlAbsoluteSlot',controlSlot,'DataAbsoluteSlot',controlSlot+f.timing_offset_slots, ...
    'TimeDomainAssignmentIndex',f.time_domain_assignment_index, ...
    'TimingOffsetSlots',f.timing_offset_slots,'PRBStart',f.prb_start,'NumPRB',f.num_prb, ...
    'SymbolAllocation',[f.symbol_start f.num_symbols], ...
    'MCS',f.mcs,'MCSTable',string(root.mcsTable),'Modulation',string(profile.Modulation), ...
    'TargetCodeRate',profile.TargetCodeRate,'RequiresHARQHistory',profile.RequiresHARQHistory, ...
    'HARQProcess',f.harq_process,'NDI',f.ndi,'RV',f.rv, ...
    'NumLayers',rank,'DMRSPortSet',double(f.dmrs_port_set(:).'), ...
    'DMRSPortIndexDomain',"zero_based_logical_DMRS_port", ...
    'NumCDMGroupsWithoutData',f.dmrs_num_cdm_groups_without_data, ...
    'DMRSFrontLoadSymbols',f.dmrs_front_load_symbols,'NSCID',f.dmrs_sequence_initialization, ...
    'AntennaPortCodepoint',f.antenna_ports,'Fields',f, ...
    'Source',"received_dci_bits_plus_installed_connected_context",'ExecutionQualified',false);
if isfield(profile,'StandardNR') && ~profile.StandardNR
    assignment.StandardNR=false;
    assignment.ResearchClass=profile.ResearchClass;
    assignment.MCSSemantics="installed_experimental_codepoints_not_NR_MCS";
end
if decoded.Direction=="UL"
    assignment.TPMI=f.precoding_information_and_number_of_layers_tpmi;
    assignment.SRSResourceIndex=f.srs_resource_index0based;
    assignment.SRSResourceSelectionSource=f.srs_resource_selection_source;
    assignment.ULSCHIndicator=f.ul_sch_indicator;
else
    assignment.K1Slots=f.pdsch_to_harq_feedback_timing_slots;
    assignment.HARQFeedbackAbsoluteSlot=assignment.DataAbsoluteSlot+assignment.K1Slots;
    assignment.PUCCHResourceIndicator=f.pucch_resource_indicator;
    assignment.TCIPresent=logical(d.ConnectedPolicy.tci_present);
    if assignment.TCIPresent
        % A received codepoint is not an activated QCL/TCI state ID.
        assignment.TCICodepoint=f.transmission_configuration_indication;
    elseif isfield(cfg.phy.pdcch.operatorControl,'coreset_qcl_association')
        expected=sixgr.pdsch.CORESETQCLReference.fromInstalled(cfg,context,controlSlot);
        assert(isfield(info,'ReceiverCORESETQCLReference') && ...
            isequaln(info.ReceiverCORESETQCLReference,expected), ...
            'sixgr:qcl:MissingReceivedCORESETAssociation', ...
            'The association must be the one bound at actual PDCCH reception.');
        assignment.ReceivedCORESETQCLReference=info.ReceiverCORESETQCLReference;
    end
end
assignment.AssignmentDigest=string(sixgr.rrc.asn1.asn1SHA256Hex(uint8( ...
    unicode2native(jsonencode(orderfields(assignment)),'UTF-8'))));
end
