classdef PDCCHTransmitter
    %PDCCHTRANSMITTER Strict intent-to-waveform PDCCH production chain.

    methods (Static)
        function result = transmit(strictCfg, fields, context, varargin)
            p = inputParser;
            addParameter(p, "AggregationLevel", strictCfg.AggregationLevel, ...
                @(x) isnumeric(x) && isscalar(x));
            addParameter(p, "CandidateIndex", 0, ...
                @(x) isnumeric(x) && isscalar(x));
            addParameter(p, "AbsoluteSlot", 0, ...
                @(x) isnumeric(x) && isscalar(x));
            parse(p, varargin{:});
            opt = p.Results;

            if string(sixgr.util.structGet(strictCfg, "ExecutionProfile", "")) ~= ...
                    "connected_blind_strict"
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "Strict transmitter requires connected_blind_strict configuration.");
            end
            context = sixgr.phy.pdcch.DCISchemaEngine.requireContext(context);
            localRequireInstalledContext(strictCfg, context);
            aggregationLevel = double(opt.AggregationLevel);
            sixgr.phy.pdcch.PDCCHSpecificationProfile.encodedBits(aggregationLevel);
            candidateCount = localCandidateCount(strictCfg, aggregationLevel);
            candidateIndex = double(opt.CandidateIndex);
            if candidateIndex < 0 || candidateIndex >= candidateCount || ...
                    candidateIndex ~= fix(candidateIndex)
                error("sixgr:phy:pdcch:invalid_candidate_count", ...
                    "CandidateIndex %g is outside the configured AL%d candidate set.", ...
                    candidateIndex, aggregationLevel);
            end
            dci = sixgr.phy.pdcch.DCIPacker.pack(fields, context);
            nCCE = strictCfg.CORESETDefinition.Data.NCCE;
            candidates = sixgr.phy.pdcch.PDCCHCandidateEnumerator.enumerate( ...
                strictCfg.SearchSpaceDefinition.Data.SearchSpaceType, ...
                nCCE, aggregationLevel, candidateCount, ...
                strictCfg.CORESETId, context.Data.RNTIValue, ...
                double(opt.AbsoluteSlot), strictCfg.SearchSpaceDefinition.Data.NCI);

            toolbox = sixgr.phy.pdcch.PDCCHToolboxFactory.create( ...
                strictCfg.ToolboxCarrier, strictCfg.CORESETDefinition, ...
                strictCfg.SearchSpaceDefinition, aggregationLevel, ...
                context.Data.RNTIValue, strictCfg.NCellID, ...
                context.Data.ActiveDLBWPStart, max(context.Data.ActiveDLBWPSize, ...
                context.Data.ActiveULBWPSize));
            pdcch = toolbox.PDCCH;
            if isprop(pdcch, "AllocatedCandidate")
                pdcch.AllocatedCandidate = candidateIndex + 1;
            else
                error("sixgr:phy:pdcch:toolbox_release_mismatch", ...
                    "Installed nrPDCCHConfig lacks AllocatedCandidate.");
            end
            runtimeCfg = sixgr.phy.pdcch.applyPDCCHConfigToRuntime( ...
                strictCfg.BaseConfig, strictCfg, ...
                "RNTI", context.Data.RNTIValue, ...
                "DCIFormat", context.Data.DCIFormat, ...
                "AggregationLevel", aggregationLevel);
            [tx, info] = sixgr.phy.dl.PDCCH_Tx(runtimeCfg, ...
                "Carrier", toolbox.Carrier, "PDCCH", pdcch, ...
                "DCIBits", dci.Bits, "K", numel(dci.Bits), ...
                "RNTI", context.Data.RNTIValue, ...
                "NCellID", strictCfg.NCellID);
            if string(info.DCIPayloadSource) ~= "explicit_DCIBits_argument" || ...
                    logical(info.RandomDCIPayload)
                error("sixgr:phy:pdcch:missing_required_field", ...
                    "Strict transmitter did not consume the contextual packed DCI.");
            end
            result = struct( ...
                "Waveform", tx.Waveform, ...
                "Grid", tx.Grid, ...
                "DCI", dci, ...
                "Context", context, ...
                "AggregationLevel", aggregationLevel, ...
                "CandidateIndex", candidateIndex, ...
                "FirstCCE", candidates.Rows(candidateIndex+1).FirstCCE, ...
                "CCEIndices", candidates.Rows(candidateIndex+1).CCEIndices, ...
                "Carrier", tx.Carrier, ...
                "PDCCH", tx.PDCCH, ...
                "PDCCHIndices", tx.PDCCHInd, ...
                "DMRSIndices", tx.DMRSInd, ...
                "DMRSSymbols", tx.DMRSSym, ...
                "EncodedBits", tx.DCICW, ...
                "Info", info, ...
                "WaveformID", localWaveformHash(tx.Waveform), ...
                "ProductionPath", "context_fields_to_packer_to_crc_polar_to_pdcch_qpsk_ofdm", ...
                "Status", "PASS");
        end
    end
end

function localRequireInstalledContext(strictCfg, context)
if ~isfield(strictCfg, "DCIContexts")
    error("sixgr:phy:pdcch:missing_dci_context", ...
        "Strict config has no installed DCI context registry.");
end
digests = strings(numel(strictCfg.DCIContexts), 1);
for ii = 1:numel(digests)
    digests(ii) = strictCfg.DCIContexts{ii}.Digest;
end
if ~any(digests == context.Digest)
    error("sixgr:phy:pdcch:wrong_dci_context", ...
        "DCI context %s is not installed in this strict configuration.", ...
        context.Digest);
end
end

function count = localCandidateCount(strictCfg, aggregationLevel)
levels = [1 2 4 8 16];
counts = [strictCfg.NumCandidatesAL1 strictCfg.NumCandidatesAL2 ...
    strictCfg.NumCandidatesAL4 strictCfg.NumCandidatesAL8 ...
    strictCfg.NumCandidatesAL16];
idx = find(levels == aggregationLevel, 1);
if isempty(idx)
    error("sixgr:phy:pdcch:invalid_aggregation_level", ...
        "Aggregation level %g is not permitted.", aggregationLevel);
end
count = double(counts(idx));
if count < 1
    error("sixgr:phy:pdcch:invalid_candidate_count", ...
        "No candidates are configured at aggregation level %d.", aggregationLevel);
end
end

function value = localWaveformHash(waveform)
samples = single([real(waveform(:)); imag(waveform(:))]);
value = string(sixgr.rrc.asn1.asn1SHA256Hex(typecast(samples, "uint8")));
end
