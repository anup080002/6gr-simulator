classdef ConnectedPDCCHConfiguration
    % Independent TX/RX materialization from installed configuration only.
    methods (Static)
        function validatePolicy(p)
            names={'cce_reg_mapping','reg_bundle_size','interleaver_size','shift_index', ...
                'precoder_granularity','start_symbol','period_slots','offset_slots', ...
                'duration_slots','dmrs_scrambling_id'};
            assert(isstruct(p) && isscalar(p) && all(isfield(p,names)) && ...
                isempty(setdiff(fieldnames(p),names)), ...
                'sixgr:phy:pdcch:MissingConnectedMonitoring', ...
                'Connected monitoring requires the explicit CORESET, monitoring clock and DM-RS configuration.');
            validateattributes(p.dmrs_scrambling_id,{'numeric'},{'scalar','integer','>=',0,'<=',65535});
        end

        function [pdcch,resolution]=build(cfg,carrier,rnti,forReceiver)
            control=cfg.phy.pdcch.operatorControl;
            p=control.connected_monitoring;
            sixgr.phy.pdcch.ConnectedPDCCHConfiguration.validatePolicy(p);
            context=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,'1_1');
            d=context.Data;
            assert(rnti==d.RNTIValue,'sixgr:phy:pdcch:ConnectedMonitoringIdentityMismatch', ...
                'Connected PDCCH identity must match the receiver-installed C-RNTI.');
            bitmap=double(cfg.phy.pdcch.coreset.frequencyResources(:).');
            enabled=find(bitmap==1);
            assert(~isempty(enabled) && all(bitmap==0 | bitmap==1) && ...
                isequal(enabled,enabled(1):enabled(end)), ...
                'sixgr:phy:pdcch:UnsupportedConnectedCORESETBitmap', ...
                'This validated CORESET factory requires contiguous configured six-RB groups.');
            core=sixgr.phy.pdcch.CORESETDefinition(struct( ...
                'CORESETID',d.CORESETID,'NRB',6*numel(enabled), ...
                'DurationSymbols',cfg.phy.pdcch.coreset.duration, ...
                'MappingType',p.cce_reg_mapping,'REGBundleSize',p.reg_bundle_size, ...
                'InterleaverSize',p.interleaver_size,'ShiftIndex',p.shift_index, ...
                'RBStart',6*(enabled(1)-1),'StartSymbol',p.start_symbol, ...
                'PrecoderGranularity',p.precoder_granularity));
            validateattributes(p.start_symbol,{'numeric'},{'scalar','integer','nonnegative'});
            assert(p.start_symbol+core.Data.DurationSymbols<=carrier.SymbolsPerSlot, ...
                'sixgr:phy:pdcch:InvalidConnectedMonitoringClock','CORESET must fit the configured slot.');
            monitoring=false(1,carrier.SymbolsPerSlot); monitoring(p.start_symbol+1)=true;
            [counts,resolution]=sixgr.phy.pdcch.resolveSearchSpaceCandidates( ...
                cfg.phy.pdcch.searchSpace.configuredNumCandidates,bitmap, ...
                core.Data.DurationSymbols,cfg.phy.pdcch.aggregationLevels);
            search=sixgr.phy.pdcch.SearchSpaceDefinition(struct( ...
                'SearchSpaceID',d.SearchSpaceID,'SearchSpaceType',d.SearchSpaceType, ...
                'CORESETID',d.CORESETID,'PeriodSlots',p.period_slots,'OffsetSlots',p.offset_slots, ...
                'DurationSlots',p.duration_slots,'MonitoringSymbolsWithinSlot',monitoring, ...
                'NumCandidates',counts,'MonitoredFormats',d.MonitoredFormats, ...
                'AllowedRNTITypes',d.RNTIType,'NCI',0));
            levels=[1 2 4 8 16];
            if forReceiver
                % nrPDCCHSpace enumerates every configured level. The
                % nominal object level is unrelated to the transmitted AL.
                level=levels(find(counts>0,1));
            else
                level=double(cfg.phy.pdcch.aggregationLevel);
            end
            assert(isscalar(level) && any(level==levels(counts>0)), ...
                'sixgr:phy:pdcch:selected_aggregation_level_unavailable','No valid configured PDCCH aggregation level.');
            objects=sixgr.phy.pdcch.PDCCHToolboxFactory.create(carrier,core,search, ...
                level,rnti,p.dmrs_scrambling_id,d.ActiveDLBWPStart,d.ActiveDLBWPSize);
            pdcch=objects.PDCCH;
        end
    end
end
