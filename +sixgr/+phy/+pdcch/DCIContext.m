classdef DCIContext
    %DCICONTEXT Immutable sizing, identity and semantic context for one DCI.

    properties (SetAccess = private)
        Data
        Digest
    end

    methods
        function obj = DCIContext(data)
            if nargin ~= 1 || ~isstruct(data) || ~isscalar(data)
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "DCIContext requires one scalar context structure.");
            end
            data = sixgr.phy.pdcch.DCIContext.normalize(data);
            sixgr.phy.pdcch.DCIContext.validate(data);
            obj.Data = data;
            obj.Digest = sixgr.phy.pdcch.DCIContext.hash(data);
        end

        function value = value(obj, name)
            name = char(string(name));
            if ~isfield(obj.Data, name)
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "DCIContext field '%s' is not installed.", name);
            end
            value = obj.Data.(name);
        end

        function out = toStruct(obj)
            out = obj.Data;
            out.ContextDigest = obj.Digest;
        end
    end

    methods (Static)
        function obj = fromLegacy(pdcchCfg, dciFormat)
            %FROMLEGACY Explicit compatibility adapter for pre-context callers.
            if ~(isstruct(pdcchCfg) && isscalar(pdcchCfg))
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "Legacy DCI configuration must be a scalar structure.");
            end
            nGrid = double(sixgr.util.structGet(pdcchCfg, "NSizeGrid", NaN));
            if ~(isscalar(nGrid) && isfinite(nGrid) && nGrid >= 1 && nGrid == fix(nGrid))
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "Legacy DCI configuration requires integer NSizeGrid >= 1.");
            end
            fmt = sixgr.phy.pdcch.normalizeDCIFormat(dciFormat);
            rntiType = sixgr.phy.pdcch.normalizeRNTIType( ...
                sixgr.util.structGet(pdcchCfg, "RNTIType", "C-RNTI"));
            searchSpaceType = upper(string(sixgr.util.structGet( ...
                pdcchCfg, "SearchSpaceType", "USS")));
            if any(searchSpaceType == ["UE","UE_SPECIFIC"])
                searchSpaceType = "USS";
            elseif any(searchSpaceType == ["COMMON","TYPE0","TYPE0A","TYPE1","TYPE2","TYPE3"])
                searchSpaceType = "CSS";
            end
            if any(fmt == ["0_0","1_0"])
                monitoredFormats = ["0_0","1_0"];
            else
                monitoredFormats = fmt;
            end
            configuredFormats = string(sixgr.util.structGet( ...
                pdcchCfg, "MonitoredFormats", monitoredFormats));
            if ~isempty(configuredFormats)
                monitoredFormats = configuredFormats(:).';
            end
            tciPresent = fmt == "1_1";
            cbgPresent = fmt == "1_1";
            data = struct( ...
                "SpecRelease", "Release-18", ...
                "SpecVersion", "18.8.0", ...
                "DCIFormat", fmt, ...
                "RNTIType", rntiType, ...
                "RNTIValue", double(sixgr.util.structGet(pdcchCfg, "RNTIValue", 4660)), ...
                "SearchSpaceType", searchSpaceType, ...
                "SearchSpaceID", double(sixgr.util.structGet(pdcchCfg, "SearchSpaceId", 1)), ...
                "CORESETID", double(sixgr.util.structGet(pdcchCfg, "CORESETId", 0)), ...
                "ControlServingCell", 0, ...
                "ControlCarrier", 0, ...
                "ControlBWP", 0, ...
                "ScheduledServingCell", 0, ...
                "ScheduledCarrier", 0, ...
                "ScheduledBWP", 0, ...
                "InitialDLBWPSize", nGrid, ...
                "InitialDLBWPStart", 0, ...
                "ActiveDLBWPSize", nGrid, ...
                "ActiveDLBWPStart", 0, ...
                "InitialULBWPSize", nGrid, ...
                "InitialULBWPStart", 0, ...
                "ActiveULBWPSize", nGrid, ...
                "ActiveULBWPStart", 0, ...
                "FrequencyAllocationType", "type1_riv", ...
                "DLTimeDomainAllocations", sixgr.phy.pdcch.DCIContext.defaultDLAllocations(), ...
                "ULTimeDomainAllocations", sixgr.phy.pdcch.DCIContext.defaultULAllocations(), ...
                "CarrierIndicatorPresent", false, ...
                "CarrierIndicatorWidth", 0, ...
                "CarrierIndicatorValue", 0, ...
                "BWPIndicatorPresent", false, ...
                "BWPIndicatorWidth", 0, ...
                "SULIndicatorPresent", false, ...
                "FrequencyHoppingEnabled", false, ...
                "TransformPrecodingEnabled", false, ...
                "HARQProcessCount", 16, ...
                "DAIWidth", 2, ...
                "AntennaPortFieldWidth", 5, ...
                "LayerCapability", 4, ...
                "TCIPresent", tciPresent, ...
                "TCIWidth", 3 * double(tciPresent), ...
                "ActiveTCIStateID", 0, ...
                "SRSResourceIndicatorWidth", 4, ...
                "SRSRequestWidth", 2, ...
                "CSIRequestWidth", 2, ...
                "RateMatchIndicatorWidth", 2, ...
                "ZPCSIRSTriggerWidth", 2, ...
                "CBGFieldsPresent", cbgPresent, ...
                "CBGTransmissionWidth", 8 * double(cbgPresent), ...
                "CBGFlushWidth", double(cbgPresent), ...
                "DMRSSequenceInitializationPresent", true, ...
                "MonitoredFormats", monitoredFormats, ...
                "ConfigurationEpoch", double(sixgr.util.structGet(pdcchCfg, "ConfigurationEpoch", 1)), ...
                "ExecutionProfile", "legacy_explicit_context_adapter", ...
                "ResearchClass", "baseline_benchmark", ...
                "LegacyCompatibility", true);
