    methods (Static, Access = private)
        function data = normalize(data)
            textFields = ["SpecRelease","SpecVersion","DCIFormat","RNTIType", ...
                "SearchSpaceType","FrequencyAllocationType","ExecutionProfile", ...
                "ResearchClass"];
            for ii = 1:numel(textFields)
                name = char(textFields(ii));
                if isfield(data, name)
                    data.(name) = string(data.(name));
                end
            end
            if isfield(data, "DCIFormat")
                data.DCIFormat = sixgr.phy.pdcch.normalizeDCIFormat(data.DCIFormat);
            end
            if isfield(data, "RNTIType")
                data.RNTIType = sixgr.phy.pdcch.normalizeRNTIType(data.RNTIType);
            end
            if isfield(data, "SearchSpaceType")
                data.SearchSpaceType = upper(strrep(string(data.SearchSpaceType), "-", "_"));
            end
            if isfield(data, "MonitoredFormats")
                values = string(data.MonitoredFormats(:));
                for ii = 1:numel(values)
                    values(ii) = sixgr.phy.pdcch.normalizeDCIFormat(values(ii));
                end
                data.MonitoredFormats = unique(values, "stable").';
            end
        end

        function validate(data)
            if isfield(data,"RNTIType") && string(data.RNTIType) == "TC-RNTI" && ...
                    isfield(data,'DCIFormat') && string(data.DCIFormat)=="1_0"
                sixgr.phy.pdcch.TCMsg4DCIContext.validate(data);
                return;
            end
            if isfield(data,"RNTIType") && string(data.RNTIType) == "RA-RNTI"
                % RA-RNTI does not carry connected-mode HARQ, UL, TCI or
                % carrier-indicator fields. Validate its own authority;
                % do not manufacture an irrelevant C-RNTI configuration.
                sixgr.phy.pdcch.RARDCIContext.validate(data);
                return;
            end
            required = ["SpecRelease","SpecVersion","DCIFormat","RNTIType", ...
                "RNTIValue","SearchSpaceType","SearchSpaceID","CORESETID", ...
                "ControlServingCell","ControlCarrier","ControlBWP", ...
                "ScheduledServingCell","ScheduledCarrier","ScheduledBWP", ...
                "InitialDLBWPSize","InitialDLBWPStart","ActiveDLBWPSize", ...
                "ActiveDLBWPStart","InitialULBWPSize","InitialULBWPStart", ...
                "ActiveULBWPSize","ActiveULBWPStart","FrequencyAllocationType", ...
                "DLTimeDomainAllocations","ULTimeDomainAllocations", ...
                "CarrierIndicatorPresent","CarrierIndicatorWidth", ...
                "CarrierIndicatorValue","BWPIndicatorPresent","BWPIndicatorWidth", ...
                "SULIndicatorPresent","FrequencyHoppingEnabled", ...
                "TransformPrecodingEnabled","HARQProcessCount","DAIWidth", ...
                "AntennaPortFieldWidth","LayerCapability","TCIPresent", ...
                "TCIWidth","ActiveTCIStateID","SRSResourceIndicatorWidth", ...
                "SRSRequestWidth","CSIRequestWidth","RateMatchIndicatorWidth", ...
                "ZPCSIRSTriggerWidth","CBGFieldsPresent","CBGTransmissionWidth", ...
                "CBGFlushWidth","DMRSSequenceInitializationPresent", ...
                "MonitoredFormats","ConfigurationEpoch","ExecutionProfile", ...
                "ResearchClass","LegacyCompatibility"];
            missing = required(~isfield(data, cellstr(required)));
            if ~isempty(missing)
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "DCIContext is missing required fields: %s.", strjoin(missing, ", "));
            end
            if ~ismember(string(data.DCIFormat), ["0_0","0_1","1_0","1_1"])
                error("sixgr:phy:pdcch:unsupported_dci_format", ...
                    "DCIFormat must be one of 0_0, 0_1, 1_0 or 1_1.");
            end
            if ~ismember(string(data.SearchSpaceType), ...
                    ["CSS","USS","TYPE0","TYPE0A","TYPE1","TYPE2","TYPE3"])
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "SearchSpaceType must identify CSS, USS or a Type0-Type3 common space.");
            end
            integerPositive = ["InitialDLBWPSize","ActiveDLBWPSize", ...
                "InitialULBWPSize","ActiveULBWPSize","HARQProcessCount"];
            for ii = 1:numel(integerPositive)
                name = char(integerPositive(ii));
                value = double(data.(name));
                if ~(isscalar(value) && isfinite(value) && value >= 1 && value == fix(value))
                    error("sixgr:phy:pdcch:missing_dci_context", ...
                        "DCIContext.%s must be a positive integer.", name);
                end
            end
            widths = ["CarrierIndicatorWidth","BWPIndicatorWidth","DAIWidth", ...
                "AntennaPortFieldWidth","TCIWidth","SRSResourceIndicatorWidth", ...
                "SRSRequestWidth","CSIRequestWidth","RateMatchIndicatorWidth", ...
                "ZPCSIRSTriggerWidth","CBGTransmissionWidth","CBGFlushWidth"];
            for ii = 1:numel(widths)
                name = char(widths(ii));
                value = double(data.(name));
                if ~(isscalar(value) && isfinite(value) && value >= 0 && value == fix(value))
                    error("sixgr:phy:pdcch:missing_dci_context", ...
                        "DCIContext.%s must be a nonnegative integer width.", name);
                end
            end
            if logical(data.CarrierIndicatorPresent) ~= (double(data.CarrierIndicatorWidth) > 0)
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "CarrierIndicatorPresent must agree with CarrierIndicatorWidth.");
            end
            if logical(data.BWPIndicatorPresent) ~= (double(data.BWPIndicatorWidth) > 0)
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "BWPIndicatorPresent must agree with BWPIndicatorWidth.");
            end
            if logical(data.TCIPresent) ~= (double(data.TCIWidth) > 0)
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "TCIPresent must agree with TCIWidth.");
            end
            if ~(ismatrix(data.DLTimeDomainAllocations) && size(data.DLTimeDomainAllocations, 2) >= 3 ...
                    && ~isempty(data.DLTimeDomainAllocations))
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "DLTimeDomainAllocations must be a nonempty numeric allocation table.");
            end
            if ~(ismatrix(data.ULTimeDomainAllocations) && size(data.ULTimeDomainAllocations, 2) >= 3 ...
                    && ~isempty(data.ULTimeDomainAllocations))
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "ULTimeDomainAllocations must be a nonempty numeric allocation table.");
            end
            epoch = double(data.ConfigurationEpoch);
            if ~(isscalar(epoch) && isfinite(epoch) && epoch >= 0 && epoch == fix(epoch))
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "ConfigurationEpoch must be a nonnegative integer.");
            end
        end

        function value = hash(data)
            ordered = orderfields(data);
            bytes = uint8(unicode2native(jsonencode(ordered), "UTF-8"));
            value = string(sixgr.rrc.asn1.asn1SHA256Hex(bytes));
        end
    end
