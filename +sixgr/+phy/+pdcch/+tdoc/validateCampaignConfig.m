function validateCampaignConfig(cfg)
%VALIDATECAMPAIGNCONFIG Fail-fast validation for AI 10.5.2.1 YAML.

required = ["strict_mode","campaign_mode","run_id","output_root", ...
    "source","reproducibility","output","common_evm","analytical", ...
    "scheduler","waveform"];
localRequireFields(cfg, required, "pdcch_tdoc10521");
if ~logical(cfg.strict_mode)
    error("sixgr:phy:pdcch:tdoc:StrictModeRequired", ...
        "pdcch_tdoc10521.strict_mode must be true.");
end
if ~ismember(lower(string(cfg.campaign_mode)), ["bounded_tdoc","full_tdoc"])
    error("sixgr:phy:pdcch:tdoc:BadCampaignMode", ...
        "campaign_mode must be bounded_tdoc or full_tdoc.");
end
localRequireFields(cfg.reproducibility, ...
    ["seed_master","seed_channel","seed_payload","seed_scheduler","deterministic"], ...
    "reproducibility");
localRequireFields(cfg.output, ...
    ["png_dpi","png_only","save_csv","save_mat","save_json", ...
    "save_resolved_yaml","save_markdown","save_html"], "output");
if double(cfg.output.png_dpi) < 300
    error("sixgr:phy:pdcch:tdoc:BadPNGResolution", ...
        "output.png_dpi must be at least 300.");
end
if ~logical(cfg.output.png_only)
    error("sixgr:phy:pdcch:tdoc:RasterOnlyRequired", ...
        "output.png_only must be true to honor the repository publication policy.");
end
a = cfg.analytical;
localRequireFields(a, ["re_per_rb_symbol","qpsk_bits_per_symbol", ...
    "dmrs_re_per_reg","cce_sizes_reg","total_reg","payload_bits", ...
    "aggregation_levels_feasibility","segment_rb","segment_duration_symbols", ...
    "reg_bundle_sizes","interleaver_r","wideband_coreset_rb","scs_hz", ...
    "cce_budget_rb","cce_budget_duration_symbols", ...
    "cce_budget_aggregation_levels","enumeration_n_cce", ...
    "enumeration_segments","enumeration_monitored_segments", ...
    "enumeration_candidate_counts","enumeration_aggregation_levels", ...
    "polar_n_max","flat_bitmap_rb"], "analytical");
if double(a.re_per_rb_symbol) ~= 12
    error("sixgr:phy:pdcch:tdoc:BadREGGeometry", ...
        "analytical.re_per_rb_symbol must be 12 for an NR REG.");
end
if numel(a.enumeration_candidate_counts) ~= ...
        numel(a.enumeration_aggregation_levels)
    error("sixgr:phy:pdcch:tdoc:BadEnumerationShape", ...
        "Candidate counts and aggregation levels must have equal length.");
end
s = cfg.scheduler;
localRequireFields(s, ["enabled","reproduction_monitoring_occasions", ...
    "short_sensitivity_monitoring_occasions","loads","extended_loads", ...
    "n_cce","segment_count","confined_fraction","aggregation_levels", ...
    "low_band_al_probability","midband_al_probability","candidate_counts", ...
    "confined_fraction_sweep","segment_count_sweep","cce_size_reg_sweep", ...
    "continuous_required_reg","coreset0_rb","coreset0_duration_symbols", ...
    "wideband_ue_fraction_sweep","mrss_overlap_fraction","mrss_rat5g_share", ...
    "monitoring_first_symbols","monitoring_consecutive_symbols", ...
    "monitoring_coreset_duration","rf_carrier_bandwidth_mhz", ...
    "rf_processing_segments","pairing_trials", ...
    "table10_tolerance_percentage_points","table10_expected"], "scheduler");
if abs(sum(double(s.low_band_al_probability)) - 1) > 1e-12 || ...
        abs(sum(double(s.midband_al_probability)) - 1) > 1e-12
    error("sixgr:phy:pdcch:tdoc:BadALDistribution", ...
        "Each scheduler AL probability vector must sum to one.");
end
w = cfg.waveform;
localRequireFields(w, ["enabled","base_scenario","evidence_class", ...
    "execution_profile","known_location_fallback","oracle_candidate_timing", ...
    "carrier_frequency_hz","band_name","duplex_mode","bandwidth_hz","scs_khz","n_size_grid", ...
    "coreset_duration_symbols","coreset_frequency_resources", ...
    "coreset_mapping","reg_bundle_size","interleaver_size", ...
    "coreset_start_symbol","ssb_case","ssb_lmax", ...
    "trials_per_point","aggregation_levels","snr_db","channels", ...
    "channel_delay_spread_ns","doppler_hz","signal_present", ...
    "absent_signal_trials_per_snr","false_alarm_snr_db","cfo_hz", ...
    "phase_noise_std_radians","impairment_snr_db","practical_channel_estimation", ...
    "perfect_channel_estimation","receiver","list_length","target_bler", ...
    "confidence_level","minimum_errors_for_tdoc_grade", ...
    "minimum_blocks_for_tdoc_grade","maximum_blocks_final"], "waveform");
sixgr.phy.pdcch.tdoc.EvidenceClass.require(w.evidence_class);
if logical(w.perfect_channel_estimation) || ...
        ~logical(w.practical_channel_estimation)
    error("sixgr:phy:pdcch:tdoc:PracticalCERequired", ...
        "Bounded TDoc waveform execution requires practical channel estimation and perfect CE disabled.");
end
if numel(w.channels) ~= numel(w.doppler_hz) || ...
        numel(w.channels) ~= numel(w.channel_delay_spread_ns)
    error("sixgr:phy:pdcch:tdoc:BadChannelMatrix", ...
        "channels, doppler_hz and channel_delay_spread_ns must have equal lengths.");
end
if double(w.trials_per_point) < 1
    error("sixgr:phy:pdcch:tdoc:BadTrialCount", ...
        "waveform.trials_per_point must be positive.");
end
end

function localRequireFields(value, fields, context)
missing = fields(~isfield(value, cellstr(fields)));
if ~isempty(missing)
    error("sixgr:phy:pdcch:tdoc:MissingConfigField", ...
        "%s is missing required field(s): %s.", context, strjoin(missing, ", "));
end
end
