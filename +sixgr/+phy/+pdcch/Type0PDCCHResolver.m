function result = Type0PDCCHResolver(context, varargin)
%TYPE0PDCCHRESOLVER Resolve the bounded Release-18 FR1 Type-0 CSS.
%
% The normative table constants in this file are transcribed from 3GPP
% TS 38.213 V18.8.0 Tables 13-0 through 13-6 and 13-11.  Scenario values
% select a table; they do not replace or override the normative rows.
%
% CONTEXT is an immutable receiver-known struct with these required fields:
%   FrequencyRange, SSBSCSKHz, PDCCHSCSKHz, ChannelBandwidthMHz,
%   SharedSpectrum, KSSB, CORESET0Index, SearchSpaceZero, SSBIndex,
%   InitialDLBWPStart, InitialDLBWPSize, NCellID.
%
% Optional fields:
%   Note17Band, SSBFrameNumber, ConfigurationEpoch.
%
% "TableID" is provided only to exercise a specific normative table row.
% The supplied table must match the rest of CONTEXT or resolution fails.

p = inputParser;
p.FunctionName = "sixgr.phy.pdcch.Type0PDCCHResolver";
addRequired(p, "context", @(x) isstruct(x) && isscalar(x));
addParameter(p, "TableID", "", @localTextScalar);
addParameter(p, "MonitoringFrameCount", 2, @localPositiveInteger);
parse(p, context, varargin{:});
opt = p.Results;

ctx = localNormalizeContext(context);
tableID = string(opt.TableID);
if strlength(tableID) == 0
    tableID = localSelectCORESETTable(ctx);
else
    tableID = upper(strtrim(tableID));
    localValidateTableContext(tableID, ctx);
end

coresetRow = sixgr.phy.pdcch.Type0TableCatalog.coreset0( ...
    tableID, ctx.CORESET0Index, ctx.KSSB);
monitoring = sixgr.phy.pdcch.Type0TableCatalog.searchSpace0( ...
    ctx.SearchSpaceZero);
monitoringOccasions = localMonitoringOccasions( ...
    monitoring, ctx, double(opt.MonitoringFrameCount), ...
    coresetRow.CORESETSymbols);

nCCE = floor(double(coresetRow.CORESETRBs) * ...
    double(coresetRow.CORESETSymbols) / 6);
candidateCounts = [0 0 min(4, floor(nCCE / 4)) ...
    min(2, floor(nCCE / 8)) 0];
candidates = localCandidates(nCCE, candidateCounts);
if isempty(candidates)
    error("sixgr:phy:pdcch:invalid_candidate_count", ...
        "Resolved CORESET0 has no legal Type-0 CSS PDCCH candidate.");
end

[payloadBits, payloadDetails] = sixgr.phy.pdcch.dciPayloadSizeBits( ...
    ctx.InitialDLBWPSize, "1_0");
rbStart = ctx.InitialDLBWPStart + double(coresetRow.OffsetRB);
if rbStart < ctx.InitialDLBWPStart || ...
        rbStart + double(coresetRow.CORESETRBs) > ...
        ctx.InitialDLBWPStart + ctx.InitialDLBWPSize
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "CORESET0 RB interval [%g,%g) is outside initial DL BWP [%g,%g).", ...
        rbStart, rbStart + double(coresetRow.CORESETRBs), ...
        ctx.InitialDLBWPStart, ...
        ctx.InitialDLBWPStart + ctx.InitialDLBWPSize);
end

payload = struct( ...
    "ContractVersion", "sixgr_type0_pdcch_release18/v1", ...
    "Specification", "3GPP TS 38.213 V18.8.0 clause 13", ...
    "Context", ctx, ...
    "CORESETTable", tableID, ...
    "CORESET0Index", ctx.CORESET0Index, ...
    "SearchSpaceZero", ctx.SearchSpaceZero, ...
    "MultiplexingPattern", double(coresetRow.MultiplexingPattern), ...
    "CORESETRBs", double(coresetRow.CORESETRBs), ...
    "CORESETSymbols", double(coresetRow.CORESETSymbols), ...
    "OffsetRB", double(coresetRow.OffsetRB), ...
    "RBStart", double(rbStart), ...
    "MonitoringTable", string(monitoring.Table), ...
    "O", double(monitoring.O), ...
    "M", double(monitoring.M), ...
    "SearchSpaceSetsPerSlot", ...
        double(monitoring.SearchSpaceSetsPerSlot), ...
    "FirstSymbolRule", string(monitoring.FirstSymbolRule), ...
    "NCCE", double(nCCE), ...
    "CandidateCounts", double(candidateCounts), ...
    "DCIPayloadBits", double(payloadBits), ...
    "DCIPayloadSizeSource", string(payloadDetails.SizeSource), ...
    "ConfigurationEpoch", ctx.ConfigurationEpoch);

result = payload;
result.CORESET0 = struct( ...
    "CORESETID", 0, ...
    "Table", tableID, ...
    "Index", ctx.CORESET0Index, ...
    "Pattern", "multiplexing_pattern_" + ...
        string(coresetRow.MultiplexingPattern), ...
    "RBStart", double(rbStart), ...
    "NumRB", double(coresetRow.CORESETRBs), ...
    "DurationSymbols", double(coresetRow.CORESETSymbols), ...
    "OffsetRB", double(coresetRow.OffsetRB), ...
    "FrequencyResourceBitmap", ...
        ones(1, double(coresetRow.CORESETRBs) / 6), ...
    "REGBundleSize", 6, ...
    "InterleaverSize", 2, ...
    "ShiftIndex", ctx.NCellID);
result.SearchSpace0 = struct( ...
    "SearchSpaceID", 0, ...
    "CORESETID", 0, ...
    "Table", string(monitoring.Table), ...
    "Index", ctx.SearchSpaceZero, ...
    "O", double(monitoring.O), ...
    "M", double(monitoring.M), ...
    "SearchSpaceSetsPerSlot", ...
        double(monitoring.SearchSpaceSetsPerSlot), ...
    "FirstSymbolRule", string(monitoring.FirstSymbolRule), ...
    "SlotPeriod", double(monitoringOccasions.PeriodSlots(1)), ...
    "SlotOffset", double(monitoringOccasions.AbsoluteSlot(1)), ...
    "DurationSlots", 1, ...
    "StartSymbolWithinSlot", ...
        double(monitoringOccasions.FirstSymbol(1)), ...
    "AggregationLevel", 4, ...
    "AggregationLevels", [4 8], ...
    "NumCandidates", double(candidateCounts));
result.MonitoringOccasions = monitoringOccasions;
result.Candidates = candidates;
result.DCIPayloadDetails = payloadDetails;
result.Type0PDCCHCSS = struct( ...
    "RNTI", 65535, ...
    "RNTIType", "SI-RNTI", ...
    "PDCCHScramblingRNTI", 0, ...
    "DCIFormat", "1_0", ...
    "DCIPayloadBits", double(payloadBits), ...
    "CandidateCounts", double(candidateCounts), ...
    "DerivedFrom", ...
        "decoded_mib_and_immutable_carrier_context");
result.ContextSHA256 = sixgr.util.sha256Hex(jsonencode(ctx));
result.ResolutionSHA256 = sixgr.util.sha256Hex(jsonencode(payload));
result.ProxyUsed = false;
result.FallbackUsed = false;
result.Status = "resolved";
end

function ctx = localNormalizeContext(context)
ctx = struct();
ctx.FrequencyRange = upper(strtrim(string(localRequire( ...
    context, "FrequencyRange"))));
if ctx.FrequencyRange ~= "FR1"
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "The bounded initial-access Type-0 resolver supports FR1.");
end
ctx.SSBSCSKHz = localInteger(localRequire(context, "SSBSCSKHz"), ...
    "SSBSCSKHz");
ctx.PDCCHSCSKHz = localInteger( ...
    localRequire(context, "PDCCHSCSKHz"), "PDCCHSCSKHz");
ctx.ChannelBandwidthMHz = localPositive( ...
    localRequire(context, "ChannelBandwidthMHz"), ...
    "ChannelBandwidthMHz");
ctx.SharedSpectrum = localLogicalScalar( ...
    localRequire(context, "SharedSpectrum"), "SharedSpectrum");
ctx.Note17Band = localLogicalScalar( ...
    localGet(context, "Note17Band", false), "Note17Band");
ctx.KSSB = localInteger(localRequire(context, "KSSB"), "KSSB");
if ctx.KSSB < 0 || ctx.KSSB > 31
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "KSSB must be an integer in [0,31].");
end
ctx.CORESET0Index = localInteger( ...
    localRequire(context, "CORESET0Index"), "CORESET0Index");
ctx.SearchSpaceZero = localInteger( ...
    localRequire(context, "SearchSpaceZero"), "SearchSpaceZero");
if ctx.CORESET0Index < 0 || ctx.CORESET0Index > 15
    error("sixgr:phy:pdcch:type0_reserved_index", ...
        "controlResourceSetZero must be in [0,15].");
end
if ctx.SearchSpaceZero < 0 || ctx.SearchSpaceZero > 15
    error("sixgr:phy:pdcch:type0_searchspace_reserved_index", ...
        "searchSpaceZero must be in [0,15].");
end
ctx.SSBIndex = localInteger(localRequire(context, "SSBIndex"), ...
    "SSBIndex");
if ctx.SSBIndex < 0
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "SSBIndex must be nonnegative.");
end
ctx.SSBFrameNumber = localInteger( ...
    localGet(context, "SSBFrameNumber", 0), "SSBFrameNumber");
ctx.InitialDLBWPStart = localInteger( ...
    localRequire(context, "InitialDLBWPStart"), ...
    "InitialDLBWPStart");
ctx.InitialDLBWPSize = localInteger( ...
    localRequire(context, "InitialDLBWPSize"), "InitialDLBWPSize");
if ctx.InitialDLBWPStart < 0 || ctx.InitialDLBWPSize < 1
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "Initial DL BWP start/size are invalid.");
end
ctx.NCellID = localInteger(localRequire(context, "NCellID"), ...
    "NCellID");
if ctx.NCellID < 0 || ctx.NCellID > 1007
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "NCellID must be in [0,1007].");
end
ctx.ConfigurationEpoch = uint64(localInteger( ...
    localGet(context, "ConfigurationEpoch", 1), ...
    "ConfigurationEpoch"));
end

function tableID = localSelectCORESETTable(ctx)
ssb = ctx.SSBSCSKHz;
pdcch = ctx.PDCCHSCSKHz;
if ctx.SharedSpectrum
    if ssb == 15 && pdcch == 15
        tableID = "13-1A";
    elseif ssb == 30 && pdcch == 30
        tableID = "13-4A";
    else
        error("sixgr:phy:pdcch:type0_context_not_supported", ...
            "No FR1 shared-spectrum Type-0 table exists for SSB/PDCCH SCS %g/%g kHz.", ...
            ssb, pdcch);
    end
    return;
end

if ssb == 15 && pdcch == 15
    if ctx.ChannelBandwidthMHz <= 3
        tableID = "13-0";
    else
        tableID = "13-1";
    end
elseif ssb == 15 && pdcch == 30
    tableID = "13-2";
elseif ssb == 30 && pdcch == 15
    if ctx.Note17Band || ctx.ChannelBandwidthMHz >= 40
        tableID = "13-5";
    else
        tableID = "13-3";
    end
elseif ssb == 30 && pdcch == 30
    if ctx.Note17Band || ctx.ChannelBandwidthMHz >= 40
        tableID = "13-6";
    else
        tableID = "13-4";
    end
else
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "No bounded FR1 Type-0 table exists for SSB/PDCCH SCS %g/%g kHz.", ...
        ssb, pdcch);
end
end

function localValidateTableContext(tableID, ctx)
valid = false;
switch tableID
    case "13-0"
        valid = ~ctx.SharedSpectrum && ctx.SSBSCSKHz == 15 && ...
            ctx.PDCCHSCSKHz == 15 && ctx.ChannelBandwidthMHz <= 5;
    case "13-1"
        valid = ~ctx.SharedSpectrum && ctx.SSBSCSKHz == 15 && ...
            ctx.PDCCHSCSKHz == 15;
    case "13-1A"
        valid = ctx.SharedSpectrum && ctx.SSBSCSKHz == 15 && ...
            ctx.PDCCHSCSKHz == 15;
    case "13-2"
        valid = ~ctx.SharedSpectrum && ctx.SSBSCSKHz == 15 && ...
            ctx.PDCCHSCSKHz == 30;
    case "13-3"
        valid = ~ctx.SharedSpectrum && ctx.SSBSCSKHz == 30 && ...
            ctx.PDCCHSCSKHz == 15 && ~ctx.Note17Band;
    case "13-4"
        valid = ~ctx.SharedSpectrum && ctx.SSBSCSKHz == 30 && ...
            ctx.PDCCHSCSKHz == 30 && ~ctx.Note17Band;
    case "13-4A"
        valid = ctx.SharedSpectrum && ctx.SSBSCSKHz == 30 && ...
            ctx.PDCCHSCSKHz == 30;
    case "13-5"
        valid = ~ctx.SharedSpectrum && ctx.SSBSCSKHz == 30 && ...
            ctx.PDCCHSCSKHz == 15;
    case "13-6"
        valid = ~ctx.SharedSpectrum && ctx.SSBSCSKHz == 30 && ...
            ctx.PDCCHSCSKHz == 30;
end
if ~valid
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "Type-0 table %s does not match the supplied FR1 context.", ...
        tableID);
end
end

function row = localCORESET0Row(tableID, index)
% Columns are [number of RBs, number of symbols, offset in RB].
switch tableID
    case "13-0"
        rows = [12 2 0;12 3 0;24 2 0;24 2 2; ...
            24 3 0;24 3 2;24 2 0;24 2 2; ...
            24 3 0;24 3 2;24 2 0;24 3 0];
    case "13-1"
        rows = [24 2 0;24 2 2;24 2 4;24 3 0; ...
            24 3 2;24 3 4;48 1 12;48 1 16; ...
            48 2 12;48 2 16;48 3 12;48 3 16; ...
            96 1 38;96 2 38;96 3 38];
    case "13-1A"
        rows = [96 1 10;96 1 12;96 1 14;96 1 16; ...
            96 2 10;96 2 12;96 2 14;96 2 16];
    case "13-2"
        rows = [24 2 5;24 2 6;24 2 7;24 2 8; ...
            24 3 5;24 3 6;24 3 7;24 3 8; ...
            48 1 18;48 1 20;48 2 18;48 2 20; ...
            48 3 18;48 3 20];
    case "13-3"
        rows = [48 1 2;48 1 6;48 2 2;48 2 6; ...
            48 3 2;48 3 6;96 1 28;96 2 28;96 3 28];
    case "13-4"
        rows = [24 2 0;24 2 1;24 2 2;24 2 3; ...
            24 2 4;24 3 0;24 3 1;24 3 2; ...
            24 3 3;24 3 4;48 1 12;48 1 14; ...
            48 1 16;48 2 12;48 2 14;48 2 16];
    case "13-4A"
        rows = [48 1 0;48 1 1;48 1 2;48 1 3; ...
            48 2 0;48 2 1;48 2 2;48 2 3];
    case "13-5"
        rows = [48 1 4;48 2 4;48 3 4;96 1 0; ...
            96 1 56;96 2 0;96 2 56;96 3 0;96 3 56];
    case "13-6"
        rows = [24 2 0;24 2 4;24 3 0;24 3 4; ...
            48 1 0;48 1 28;48 2 0;48 2 28; ...
            48 3 0;48 3 28];
    otherwise
        error("sixgr:phy:pdcch:type0_context_not_supported", ...
            "Unsupported bounded FR1 Type-0 table %s.", tableID);
end
if index + 1 > size(rows, 1)
    error("sixgr:phy:pdcch:type0_reserved_index", ...
        "controlResourceSetZero=%d is reserved in Table %s.", ...
        index, tableID);
end
values = rows(index + 1, :);
row = struct( ...
    "Table", tableID, ...
    "ControlResourceSetZero", index, ...
    "MultiplexingPattern", 1, ...
    "CORESETRBs", values(1), ...
    "CORESETSymbols", values(2), ...
    "OffsetRB", values(3));
end

