function occasions = localMonitoringOccasions(row, ctx, frameCount, nSymb)
mu = log2(double(ctx.PDCCHSCSKHz) / 15);
if mu ~= fix(mu) || mu < 0
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "PDCCH SCS %g kHz does not map to an FR1 numerology.", ...
        ctx.PDCCHSCSKHz);
end
slotsPerFrame = 10 * 2 ^ mu;
n0Raw = double(row.O) * 2 ^ mu + ...
    floor(double(ctx.SSBIndex) * double(row.M));
slotWithinFrame = mod(n0Raw, slotsPerFrame);
frameParity = mod(floor(n0Raw / slotsPerFrame), 2);
firstSymbol = localFirstSymbol( ...
    string(row.FirstSymbolRule), ctx.SSBIndex, nSymb);
startFrame = double(ctx.SSBFrameNumber);
stopFrame = startFrame + frameCount - 1;
frames = (startFrame:stopFrame).';
frames = frames(mod(frames, 2) == frameParity);
if isempty(frames)
    frames = startFrame + mod(frameParity - mod(startFrame, 2), 2);
end
absoluteSlot = frames * slotsPerFrame + slotWithinFrame;
occasionID = "type0_sfn" + string(frames) + ...
    "_slot" + string(slotWithinFrame) + ...
    "_sym" + string(firstSymbol);
occasions = table(occasionID, frames, ...
    repmat(slotWithinFrame, numel(frames), 1), ...
    absoluteSlot, repmat(firstSymbol, numel(frames), 1), ...
    repmat(2 * slotsPerFrame, numel(frames), 1), ...
    repmat(double(row.SearchSpaceSetsPerSlot), numel(frames), 1), ...
    'VariableNames', {'MonitoringOccasionID','SFN','Slot', ...
    'AbsoluteSlot','FirstSymbol','PeriodSlots', ...
    'SearchSpaceSetsPerSlot'});
end

function first = localFirstSymbol(rule, ssbIndex, nSymb)
if rule == "0_if_i_even|NsymbCORESET_if_i_odd"
    if mod(ssbIndex, 2) == 0
        first = 0;
    else
        first = double(nSymb);
    end
else
    first = str2double(rule);
end
end

function candidates = localCandidates(nCCE, counts)
levels = [1 2 4 8 16];
rows = repmat(struct( ...
    "AggregationLevel", NaN, ...
    "CandidateIndex", NaN, ...
    "FirstCCE", NaN, ...
    "CCEIndices", "", ...
    "NCCE", nCCE), 0, 1);
for ii = 1:numel(levels)
    level = levels(ii);
    count = counts(ii);
    for m = 0:count-1
        first = level * floor(m * nCCE / (level * count));
        cce = first + (0:level-1);
        rows(end + 1, 1) = struct( ... %#ok<AGROW>
            "AggregationLevel", level, ...
            "CandidateIndex", m, ...
            "FirstCCE", first, ...
            "CCEIndices", strjoin(string(cce), "|"), ...
            "NCCE", nCCE);
    end
end
if isempty(rows)
    candidates = table();
else
    candidates = struct2table(rows, "AsArray", true);
end
end

function value = localRequire(s, name)
if ~isfield(s, name) || isempty(s.(name))
    error("sixgr:phy:pdcch:missing_dci_context", ...
        "Type-0 context is missing required field %s.", name);
end
value = s.(name);
end

function value = localGet(s, name, defaultValue)
if isfield(s, name) && ~isempty(s.(name))
    value = s.(name);
else
    value = defaultValue;
end
end

function value = localInteger(value, name)
value = double(value);
if ~(isscalar(value) && isfinite(value) && value == fix(value))
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "%s must be a finite integer scalar.", name);
end
end

function value = localPositive(value, name)
value = double(value);
if ~(isscalar(value) && isfinite(value) && value > 0)
    error("sixgr:phy:pdcch:type0_context_not_supported", ...
        "%s must be a positive finite scalar.", name);
end
end

function value = localLogicalScalar(value, name)
if ischar(value) || isstring(value)
    token = lower(strtrim(string(value)));
    if token == "true"
        value = true;
    elseif token == "false"
        value = false;
    else
        error("sixgr:phy:pdcch:type0_context_not_supported", ...
            "%s must be true or false.", name);
    end
else
    value = logical(value);
    if ~isscalar(value)
        error("sixgr:phy:pdcch:type0_context_not_supported", ...
            "%s must be a logical scalar.", name);
    end
end
end

function tf = localTextScalar(value)
tf = ischar(value) || (isstring(value) && isscalar(value));
end

function tf = localPositiveInteger(value)
tf = isnumeric(value) && isscalar(value) && isfinite(value) && ...
    value >= 1 && value == fix(value);
end
