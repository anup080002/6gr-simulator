function context=validateConnectedAssignment(installed,assignment)
% Check the retained receiver capsule before a downstream consumer uses it.
assert(isstruct(assignment) && isscalar(assignment) && ...
    string(assignment.Source)=="received_dci_bits_plus_installed_connected_context", ...
    'sixgr:phy:pdcch:ConnectedReceptionRequired','A received connected assignment is required.');
body=rmfield(assignment,'AssignmentDigest');
digest=string(sixgr.rrc.asn1.asn1SHA256Hex(uint8( ...
    unicode2native(jsonencode(orderfields(body)),'UTF-8'))));
assert(digest==string(assignment.AssignmentDigest), ...
    'sixgr:phy:pdcch:ReceivedAssignmentDigestMismatch','Received assignment changed after materialization.');
context=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(installed,assignment.DCIFormat);
assert(context.Digest==assignment.ContextDigest && ...
    context.Data.ConfigurationEpoch==assignment.ConfigurationEpoch, ...
    'sixgr:phy:pdcch:stale_bwp_context','Data allocation requires the installed context used to decode DCI.');
end
