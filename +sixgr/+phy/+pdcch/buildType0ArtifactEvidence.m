function value=buildType0ArtifactEvidence(runID)
%BUILDTYPE0ARTIFACTEVIDENCE Execute the installed Type-0 timing resolver.
% These are resolved configuration occasions, not received PDCCH detections.
rows=cell(48,1);
for ii=1:numel(rows)
    ssbIndex=floor((ii-1)/16);
    searchIndex=mod(ii-1,16);
    coresetIndex=mod(ii-1,12);
    context=struct('FrequencyRange',"FR1",'SSBSCSKHz',15, ...
        'PDCCHSCSKHz',15,'ChannelBandwidthMHz',20,'SharedSpectrum',false, ...
        'KSSB',0,'CORESET0Index',coresetIndex,'SearchSpaceZero',searchIndex, ...
        'SSBIndex',ssbIndex,'InitialDLBWPStart',0,'InitialDLBWPSize',106, ...
        'NCellID',42,'SSBFrameNumber',0);
    resolved=sixgr.phy.pdcch.Type0PDCCHResolver(context,'MonitoringFrameCount',4);
    occasion=resolved.MonitoringOccasions;
    slots=double(occasion.AbsoluteSlot);
    symbols=double(occasion.FirstSymbol);
    mismatch=sum(slots~=fix(slots) | slots<0 | slots>=40 | ...
        symbols~=fix(symbols) | symbols<0 | symbols+resolved.CORESETSymbols>14);
    assert(mismatch==0,'sixgr:phy:pdcch:invalid_type0_evidence', ...
        'Resolved Type-0 occasions have invalid slot/symbol bounds.');
    rows{ii}=table(string(runID),"TYPE0"+compose('%04d',ii),"FR1",15,15, ...
        16*coresetIndex+searchIndex,coresetIndex,searchIndex, ...
        resolved.MultiplexingPattern,resolved.CORESETRBs,resolved.CORESETSymbols, ...
        resolved.OffsetRB,resolved.O,resolved.M,resolved.FirstSymbolRule, ...
        join(string(slots.'),'|'),resolved.DCIPayloadBits,mismatch,"PASS", ...
        ssbIndex,join(string(symbols.'),'|'),occasion.PeriodSlots(1), ...
        resolved.ContextSHA256,resolved.ResolutionSHA256, ...
        "resolved_configuration_not_receiver_detection","resolved_occasion_bounds", ...
        'VariableNames',{'RunID','CaseID','FR','SSBSCSkHz','PDCCHSCSkHz', ...
        'PDCCHConfigSIB1','ControlResourceSetZero','SearchSpaceZero', ...
        'MultiplexingPattern','CORESETRBs','CORESETSymbols','OffsetRB','O','M', ...
        'FirstSymbolRule','MonitoringSlots','PayloadBits','MismatchCount','Status', ...
        'SSBIndex','MonitoringFirstSymbols','PeriodSlots','ContextSHA256', ...
        'ResolutionSHA256','EvidenceClass','CheckScope'});
end
value=vertcat(rows{:});
end
