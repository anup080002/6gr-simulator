classdef PDCCHReceiver
    %PDCCHRECEIVER Strict blind monitoring with no candidate oracle.

    methods (Static)
        function result = receive(rxWaveform, strictCfg, varargin)
            p = inputParser;
            addParameter(p, "SynchronizationState", struct( ...
                "SlotBoundaryOffsetSamples", 0, "Source", "declared_aligned_slot"), ...
                @isstruct);
            addParameter(p, "NoiseVar", [], @(x) isempty(x) || ...
                (isnumeric(x) && isscalar(x) && x >= 0));
            addParameter(p, "ListLength", 8, @(x) isnumeric(x) && isscalar(x));
            addParameter(p, "AbsoluteSlot", 0, @(x) isnumeric(x) && isscalar(x));
            addParameter(p, "RunID", "pdcch_strict", @(x) ischar(x) || isstring(x));
            parse(p, varargin{:});
            opt = p.Results;
            localValidateStrictInputs(strictCfg, opt.SynchronizationState);
            syncOffset = double(sixgr.util.structGet( ...
                opt.SynchronizationState, "SlotBoundaryOffsetSamples", 0));
            if syncOffset ~= 0
                rxWaveform = localApplyDeclaredSync(rxWaveform, syncOffset);
            end
            hypothesisRows = repmat(localHypothesisRow(), 0, 1);
            passing = repmat(localPass(), 0, 1);
            levels = [1 2 4 8 16];
            counts = [strictCfg.NumCandidatesAL1 strictCfg.NumCandidatesAL2 ...
                strictCfg.NumCandidatesAL4 strictCfg.NumCandidatesAL8 ...
                strictCfg.NumCandidatesAL16];
            for contextIndex = 1:numel(strictCfg.DCIContexts)
                context = strictCfg.DCIContexts{contextIndex};
                sixgr.phy.pdcch.RNTIProcedureRegistry.validate( ...
                    context.Data.RNTIType, context.Data.RNTIValue, ...
                    strictCfg.SearchSpaceDefinition.Data.SearchSpaceType, ...
                    context.Data.DCIFormat);
                alignment = sixgr.phy.pdcch.DCISizeAlignmentEngine.resolve(context);
                for levelIndex = 1:numel(levels)
                    if counts(levelIndex) < 1
                        continue;
                    end
                    aggregationLevel = levels(levelIndex);
                    narrowedSearch = localNarrowSearchSpace( ...
                        strictCfg.SearchSpaceDefinition, levelIndex);
                    toolbox = sixgr.phy.pdcch.PDCCHToolboxFactory.create( ...
                        strictCfg.ToolboxCarrier, strictCfg.CORESETDefinition, ...
                        narrowedSearch, aggregationLevel, context.Data.RNTIValue, ...
                        strictCfg.NCellID, context.Data.ActiveDLBWPStart, ...
                        max(context.Data.ActiveDLBWPSize, context.Data.ActiveULBWPSize));
                    runtimeCfg = sixgr.phy.pdcch.applyPDCCHConfigToRuntime( ...
                        strictCfg.BaseConfig, strictCfg, ...
                        "RNTI", context.Data.RNTIValue, ...
                        "DCIFormat", context.Data.DCIFormat, ...
                        "AggregationLevel", aggregationLevel);
                    runtimeCfg = sixgr.util.structSet(runtimeCfg, ...
                        "phy.pdcch.allowBlindCandidateTimingEstimate", false);
                    args = {"Carrier", toolbox.Carrier, "PDCCH", toolbox.PDCCH, ...
                        "K", alignment.Selected.AlignedBits, ...
                        "ListLength", double(opt.ListLength), ...
                        "RNTI", context.Data.RNTIValue};
                    if ~isempty(opt.NoiseVar)
                        args = [args {"NoiseVar", double(opt.NoiseVar)}]; %#ok<AGROW>
                    end
                    [rx, info] = sixgr.phy.dl.PDCCH_Rx( ...
                        rxWaveform, runtimeCfg, args{:});
                    candidates = sixgr.phy.pdcch.PDCCHCandidateEnumerator.enumerate( ...
                        narrowedSearch.Data.SearchSpaceType, ...
                        strictCfg.CORESETDefinition.Data.NCCE, ...
                        aggregationLevel, counts(levelIndex), strictCfg.CORESETId, ...
                        context.Data.RNTIValue, double(opt.AbsoluteSlot), ...
                        narrowedSearch.Data.NCI);
                    [hypothesisRows, pass] = localRecordAttempt(hypothesisRows, ...
                        rx, info, context, aggregationLevel, candidates);
                    if ~isempty(pass)
                        passing(end+1,1) = pass; %#ok<AGROW>
                    end
                end
            end
            if numel(passing) > 1
                error("sixgr:phy:pdcch:ambiguous_valid_hypotheses", ...
                    "%d blind hypotheses passed CRC/RNTI and contextual parsing.", ...
                    numel(passing));
            end
            result = struct( ...
                "Detected", false, "DecodedDCIEvent", [], ...
                "DecodedDCI", struct(), ...
                "HypothesisTable", struct2table(hypothesisRows, "AsArray", true), ...
                "ValidHypothesisCount", numel(passing), ...
                "UsedKnownLocation", false, ...
                "UsedOracleTiming", false, ...
                "SynchronizationSource", string(sixgr.util.structGet( ...
                    opt.SynchronizationState, "Source", "declared_aligned_slot")), ...
                "Status", "NO_VALID_HYPOTHESIS");
            if isempty(passing)
                return;
            end
            selected = passing(1);
            eventData = localEventData(selected, strictCfg, opt, rxWaveform);
            event = sixgr.phy.pdcch.DecodedDCIEvent(eventData);
            result.Detected = true;
            result.DecodedDCIEvent = event;
            result.DecodedDCI = selected.Decoded;
            result.SelectedAggregationLevel = selected.AggregationLevel;
            result.SelectedCandidateIndex = selected.CandidateIndex;
            result.SelectedFirstCCE = selected.FirstCCE;
            result.Status = "PASS";
        end

        function prepared = prepare(strictCfg)
            %PREPARE Resolve receiver-visible blind hypotheses once.
            % Preparation consumes only installed configuration. It does
            % not consume a transmitted candidate, format, RNTI, or timing
            % oracle and is therefore safe to reuse across Monte Carlo
            % waveform realizations.
            localValidateStrictInputs(strictCfg, struct( ...
                "SlotBoundaryOffsetSamples", 0, ...
                "Source", "prepared_receiver_visible_configuration"));
            levels = [1 2 4 8 16];
            counts = [strictCfg.NumCandidatesAL1 strictCfg.NumCandidatesAL2 ...
                strictCfg.NumCandidatesAL4 strictCfg.NumCandidatesAL8 ...
                strictCfg.NumCandidatesAL16];
            hypotheses = repmat(localPreparedHypothesis(), 0, 1);
            for contextIndex = 1:numel(strictCfg.DCIContexts)
                context = strictCfg.DCIContexts{contextIndex};
                sixgr.phy.pdcch.RNTIProcedureRegistry.validate( ...
                    context.Data.RNTIType, context.Data.RNTIValue, ...
                    strictCfg.SearchSpaceDefinition.Data.SearchSpaceType, ...
                    context.Data.DCIFormat);
                alignment = sixgr.phy.pdcch.DCISizeAlignmentEngine.resolve(context);
                for levelIndex = 1:numel(levels)
                    if counts(levelIndex) < 1
                        continue;
                    end
                    aggregationLevel = levels(levelIndex);
                    narrowedSearch = localNarrowSearchSpace( ...
                        strictCfg.SearchSpaceDefinition, levelIndex);
                    toolbox = sixgr.phy.pdcch.PDCCHToolboxFactory.create( ...
                        strictCfg.ToolboxCarrier, strictCfg.CORESETDefinition, ...
                        narrowedSearch, aggregationLevel, ...
                        context.Data.RNTIValue, strictCfg.NCellID, ...
                        context.Data.ActiveDLBWPStart, ...
                        max(context.Data.ActiveDLBWPSize, ...
                        context.Data.ActiveULBWPSize));
                    runtimeCfg = sixgr.phy.pdcch.applyPDCCHConfigToRuntime( ...
                        strictCfg.BaseConfig, strictCfg, ...
                        "RNTI", context.Data.RNTIValue, ...
                        "DCIFormat", context.Data.DCIFormat, ...
                        "AggregationLevel", aggregationLevel);
                    runtimeCfg = sixgr.util.structSet(runtimeCfg, ...
                        "phy.pdcch.allowBlindCandidateTimingEstimate", false);
                    candidates = sixgr.phy.pdcch.PDCCHCandidateEnumerator.enumerate( ...
                        narrowedSearch.Data.SearchSpaceType, ...
                        strictCfg.CORESETDefinition.Data.NCCE, ...
                        aggregationLevel, counts(levelIndex), ...
                        strictCfg.CORESETId, context.Data.RNTIValue, 0, ...
                        narrowedSearch.Data.NCI);
                    hypothesis = localPreparedHypothesis();
                    hypothesis.Context = context;
                    hypothesis.AggregationLevel = aggregationLevel;
                    hypothesis.Carrier = toolbox.Carrier;
                    hypothesis.PDCCH = toolbox.PDCCH;
                    hypothesis.RuntimeConfig = runtimeCfg;
                    hypothesis.K = alignment.Selected.AlignedBits;
                    hypothesis.RNTI = context.Data.RNTIValue;
                    hypothesis.Candidates = candidates;
                    hypotheses(end+1,1) = hypothesis; %#ok<AGROW>
                end
            end
            if isempty(hypotheses)
                error("sixgr:phy:pdcch:invalid_candidate_count", ...
                    "Prepared strict blind receiver resolved no hypotheses.");
            end
            prepared = struct( ...
                "StrictConfig", strictCfg, ...
                "Hypotheses", hypotheses, ...
                "ConfigHash", strictCfg.ConfigHash, ...
                "KnownLocationUsed", false, ...
                "OracleTimingUsed", false, ...
                "Status", "PASS");
        end

        function result = receivePrepared(rxWaveform, prepared, varargin)
            %RECEIVEPREPARED Execute pre-resolved strict blind hypotheses.
            p = inputParser;
            addParameter(p, "SynchronizationState", struct( ...
                "SlotBoundaryOffsetSamples", 0, ...
                "Source", "declared_aligned_slot"), @isstruct);
            addParameter(p, "NoiseVar", [], @(x) isempty(x) || ...
                (isnumeric(x) && isscalar(x) && x >= 0));
            addParameter(p, "ListLength", 8, ...
                @(x) isnumeric(x) && isscalar(x));
            addParameter(p, "AbsoluteSlot", 0, ...
                @(x) isnumeric(x) && isscalar(x));
            addParameter(p, "RunID", "pdcch_strict", ...
                @(x) ischar(x) || isstring(x));
            parse(p, varargin{:});
            opt = p.Results;
            if ~(isstruct(prepared) && isfield(prepared, "StrictConfig") && ...
                    isfield(prepared, "Hypotheses"))
                error("sixgr:phy:pdcch:missing_dci_context", ...
                    "A prepared strict receiver configuration is required.");
            end
            strictCfg = prepared.StrictConfig;
            localValidateStrictInputs(strictCfg, opt.SynchronizationState);
            if string(prepared.ConfigHash) ~= string(strictCfg.ConfigHash)
                error("sixgr:phy:pdcch:stale_bwp_context", ...
                    "Prepared receiver configuration hash is stale.");
            end
            syncOffset = double(sixgr.util.structGet( ...
                opt.SynchronizationState, "SlotBoundaryOffsetSamples", 0));
            if syncOffset ~= 0
                rxWaveform = localApplyDeclaredSync(rxWaveform, syncOffset);
            end
            hypothesisRows = repmat(localHypothesisRow(), 0, 1);
            passing = repmat(localPass(), 0, 1);
            for index = 1:numel(prepared.Hypotheses)
                hypothesis = prepared.Hypotheses(index);
                args = {"Carrier", hypothesis.Carrier, ...
                    "PDCCH", hypothesis.PDCCH, ...
                    "K", hypothesis.K, ...
                    "ListLength", double(opt.ListLength), ...
                    "RNTI", hypothesis.RNTI};
                if ~isempty(opt.NoiseVar)
                    args = [args {"NoiseVar", double(opt.NoiseVar)}]; %#ok<AGROW>
                end
                [rx, info] = sixgr.phy.dl.PDCCH_Rx( ...
                    rxWaveform, hypothesis.RuntimeConfig, args{:});
                [hypothesisRows, pass] = localRecordAttempt( ...
                    hypothesisRows, rx, info, hypothesis.Context, ...
                    hypothesis.AggregationLevel, hypothesis.Candidates);
                if ~isempty(pass)
                    passing(end+1,1) = pass; %#ok<AGROW>
                end
            end
            if numel(passing) > 1
                error("sixgr:phy:pdcch:ambiguous_valid_hypotheses", ...
                    "%d prepared blind hypotheses passed.", numel(passing));
            end
            result = struct( ...
                "Detected", false, "DecodedDCIEvent", [], ...
                "DecodedDCI", struct(), ...
                "HypothesisTable", struct2table( ...
                hypothesisRows, "AsArray", true), ...
                "ValidHypothesisCount", numel(passing), ...
                "UsedKnownLocation", false, ...
                "UsedOracleTiming", false, ...
                "SynchronizationSource", string(sixgr.util.structGet( ...
                opt.SynchronizationState, "Source", ...
                "declared_aligned_slot")), ...
                "PreparedBlindSearch", true, ...
                "Status", "NO_VALID_HYPOTHESIS");
            if isempty(passing)
                return;
            end
            selected = passing(1);
            eventData = localEventData(selected, strictCfg, opt, rxWaveform);
            event = sixgr.phy.pdcch.DecodedDCIEvent(eventData);
            result.Detected = true;
            result.DecodedDCIEvent = event;
            result.DecodedDCI = selected.Decoded;
            result.SelectedAggregationLevel = selected.AggregationLevel;
            result.SelectedCandidateIndex = selected.CandidateIndex;
            result.SelectedFirstCCE = selected.FirstCCE;
            result.Status = "PASS";
        end
    end
end

function localValidateStrictInputs(strictCfg, sync)
if string(sixgr.util.structGet(strictCfg, "ExecutionProfile", "")) ~= ...
        "connected_blind_strict"
    error("sixgr:phy:pdcch:known_location_forbidden_in_blind_profile", ...
        "PDCCHReceiver only accepts connected_blind_strict configuration.");
end
if logical(sixgr.util.structGet(strictCfg, ...
        "KnownLocationFallbackAllowed", false))
    error("sixgr:phy:pdcch:known_location_forbidden_in_blind_profile", ...
        "Known-location fallback is forbidden in blind strict mode.");
end
forbiddenLocation = ["CandidateCCEIndex","CandidateIndex","FirstCCE", ...
    "TransmittedCCE","DCIFormat","RNTI"];
if any(isfield(sync, cellstr(forbiddenLocation)))
    error("sixgr:phy:pdcch:known_location_forbidden_in_blind_profile", ...
        "SynchronizationState contains candidate/format/RNTI oracle information.");
end
forbiddenTiming = ["CandidateTiming","ExactCandidateTiming", ...
    "MonitoringSymbolOracle"];
if any(isfield(sync, cellstr(forbiddenTiming))) || ...
        logical(sixgr.util.structGet(strictCfg, ...
        "OracleCandidateTimingAllowed", false))
    error("sixgr:phy:pdcch:oracle_timing_forbidden_in_blind_profile", ...
        "Candidate-specific timing is forbidden in blind strict mode.");
end
end

function narrowed = localNarrowSearchSpace(searchSpace, levelIndex)
data = searchSpace.Data;
counts = zeros(1, 5);
counts(levelIndex) = data.NumCandidates(levelIndex);
data.NumCandidates = counts;
narrowed = sixgr.phy.pdcch.SearchSpaceDefinition(data);
end

function [rows, pass] = localRecordAttempt(rows, rx, info, context, ...
        aggregationLevel, candidates)
pass = repmat(localPass(), 0, 1);
candidateTable = sixgr.util.structGet(info, "CandidateResults", table());
for ii = 1:max(1, height(candidateTable))
    row = localHypothesisRow();
    row.DCIFormat = string(context.Data.DCIFormat);
    row.RNTIType = string(context.Data.RNTIType);
    row.RNTIValue = double(context.Data.RNTIValue);
    row.AggregationLevel = aggregationLevel;
    row.CandidateIndex = ii - 1;
    if ii <= numel(candidates.Rows)
        row.FirstCCE = candidates.Rows(ii).FirstCCE;
    end
    if height(candidateTable) >= ii
        row.CRCCheckPassed = logical(candidateTable.DecodeOK(ii));
        row.DecoderMetric = 1 / (1 + max(0, double(candidateTable.EVM_rms(ii))));
    end
    row.ContextDigest = context.Digest;
    row.K = sixgr.phy.pdcch.DCISizeAlignmentEngine.resolve(context).Selected.AlignedBits;
    row.Status = "CRC_REJECT";
    if logical(rx.Ok) && double(rx.CandidateIndex) == ii
        try
            decoded = sixgr.phy.pdcch.DCIParser.parse(rx.DCIBits, context);
            row.ContextParsePassed = true;
            row.Status = "PASS";
            pass = localPass();
            pass.Context = context;
            pass.Decoded = decoded;
            pass.AggregationLevel = aggregationLevel;
            pass.CandidateIndex = ii - 1;
            pass.FirstCCE = row.FirstCCE;
            pass.Rx = rx;
        catch ME
            row.Status = "CONTEXT_REJECT:" + string(ME.identifier);
        end
    end
    rows(end+1,1) = row; %#ok<AGROW>
end
end

function data = localEventData(selected, strictCfg, opt, rxWaveform)
context = selected.Context.Data;
decoded = selected.Decoded;
data = struct( ...
    "WaveformID", localWaveformHash(rxWaveform), ...
    "RunID", string(opt.RunID), ...
    "AbsoluteSlot", double(opt.AbsoluteSlot), ...
    "MonitoringSymbol", strictCfg.SearchSpaceFirstSymbolWithinSlot, ...
    "ControlServingCell", context.ControlServingCell, ...
    "ControlCarrier", context.ControlCarrier, ...
    "ControlBWP", context.ControlBWP, ...
    "ScheduledServingCell", context.ScheduledServingCell, ...
    "ScheduledCarrier", context.ScheduledCarrier, ...
    "ScheduledBWP", context.ScheduledBWP, ...
    "SearchSpaceID", context.SearchSpaceID, ...
    "CORESETID", context.CORESETID, ...
    "AggregationLevel", selected.AggregationLevel, ...
    "CandidateIndex", selected.CandidateIndex, ...
    "FirstCCE", selected.FirstCCE, ...
    "DCIFormat", context.DCIFormat, ...
    "AlignedPayloadBits", numel(decoded.Bits), ...
    "RNTIType", context.RNTIType, ...
    "RNTIValue", context.RNTIValue, ...
    "CRCCheckPassed", true, ...
    "RNTIMatch", true, ...
    "RawPayloadBits", decoded.Bits, ...
    "RawPayloadHash", decoded.PayloadHash, ...
    "ParsedFields", decoded.Fields, ...
    "ContextDigest", selected.Context.Digest, ...
    "ConfigurationEpoch", context.ConfigurationEpoch, ...
    "TCIStateID", context.ActiveTCIStateID, ...
    "QCLSourceType", "PDCCH_DMRS", ...
    "QCLSourceID", context.CORESETID, ...
    "BeamID", context.ActiveTCIStateID, ...
    "MeasurementProvenance", "observed_pdcch_dmrs_waveform_blind_candidate");
end

function row = localHypothesisRow()
row = struct("DCIFormat", "", "RNTIType", "", "RNTIValue", NaN, ...
    "AggregationLevel", NaN, "CandidateIndex", NaN, "FirstCCE", NaN, ...
    "K", NaN, "CRCCheckPassed", false, "ContextParsePassed", false, ...
    "DecoderMetric", NaN, "ContextDigest", "", "Status", "");
end

function value = localPass()
value = struct("Context", [], "Decoded", struct(), ...
    "AggregationLevel", NaN, "CandidateIndex", NaN, ...
    "FirstCCE", NaN, "Rx", struct());
end

function value = localPreparedHypothesis()
value = struct("Context", [], "AggregationLevel", NaN, ...
    "Carrier", [], "PDCCH", [], "RuntimeConfig", struct(), ...
    "K", NaN, "RNTI", NaN, "Candidates", struct());
end

function waveform = localApplyDeclaredSync(waveform, offset)
offset = round(double(offset));
if offset > 0
    waveform = [waveform(offset+1:end,:); ...
        zeros(offset, size(waveform,2), "like", waveform)];
elseif offset < 0
    amount = abs(offset);
    waveform = [zeros(amount, size(waveform,2), "like", waveform); ...
        waveform(1:end-amount,:)];
end
end

function value = localWaveformHash(waveform)
samples = single([real(waveform(:)); imag(waveform(:))]);
value = string(sixgr.rrc.asn1.asn1SHA256Hex(typecast(samples, "uint8")));
end
