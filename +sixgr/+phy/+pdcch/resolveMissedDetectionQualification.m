function design=resolveMissedDetectionQualification(operatorStrict)
% Optional H1 design. Absence cannot qualify a detector from H0 alone.
design=struct('Enabled',false,'Scope',"awgn_component_not_nr_conformance", ...
    'ChannelModel',"AWGN",'SNRdB',zeros(1,0),'DCIFormats',strings(1,0));
if ~isfield(operatorStrict,'missed_detection_qualification'), return; end
raw=operatorStrict.missed_detection_qualification;
assert(isstruct(raw)&&isscalar(raw)&&isfield(raw,'enabled') && ...
    islogical(raw.enabled)&&isscalar(raw.enabled), ...
    'sixgr:phy:pdcch:InvalidMissedDetectionDesign', ...
    'missed_detection_qualification.enabled must be an explicit boolean.');
design.Enabled=raw.enabled;
if ~design.Enabled, return; end
fields=["scope","channel_model","snr_db","dci_formats", ...
    "target_missed_grant_probability","minimum_waveform_trials", ...
    "maximum_waveform_trials","batch_size_waveform_trials", ...
    "minimum_missed_grant_events","ci_width_target","planned_looks"];
assert(all(isfield(raw,fields)), 'sixgr:phy:pdcch:InvalidMissedDetectionDesign', ...
    'Enabled missed_detection_qualification requires every explicit scope/grid/budget field.');
design.Scope=string(raw.scope); design.ChannelModel=string(raw.channel_model);
assert(isscalar(design.Scope)&&design.Scope=="awgn_component_not_nr_conformance" && ...
    isscalar(design.ChannelModel)&&design.ChannelModel=="AWGN", ...
    'sixgr:phy:pdcch:UnsupportedQualificationContext', ...
    'This producer executes AWGN component trials, not fading/RF or NR conformance qualification.');
validateattributes(raw.snr_db,{'numeric'},{'real','finite','vector','nonempty'});
design.SNRdB=reshape(double(raw.snr_db),1,[]);
design.DCIFormats=reshape(string(raw.dci_formats),1,[]);
assert(numel(unique(design.SNRdB))==numel(design.SNRdB) && ...
    ~isempty(design.DCIFormats) && all(ismember(design.DCIFormats,["1_0","0_0"])) && ...
    numel(unique(design.DCIFormats))==numel(design.DCIFormats), ...
    'sixgr:phy:pdcch:InvalidMissedDetectionDesign','Use distinct SNRs and supported DCI formats.');
source=["target_missed_grant_probability","minimum_waveform_trials", ...
    "maximum_waveform_trials","batch_size_waveform_trials", ...
    "minimum_missed_grant_events","ci_width_target","planned_looks"];
target=["TargetProbability","MinimumWaveformTrials","MaximumWaveformTrials", ...
    "BatchSizeWaveformTrials","MinimumEvents","CIWidthTarget","PlannedLooks"];
for k=1:numel(source)
    validateattributes(raw.(source(k)),{'numeric'},{'real','finite','scalar'});
    design.(target(k))=double(raw.(source(k)));
end
ints=[design.MinimumWaveformTrials,design.MaximumWaveformTrials, ...
    design.BatchSizeWaveformTrials,design.MinimumEvents,design.PlannedLooks];
assert(all(ints==fix(ints)) && all(ints([1 2 3 5])>=1) && ints(4)>=0 && ...
    design.MaximumWaveformTrials>=design.MinimumWaveformTrials && ...
    design.MinimumEvents<=design.MaximumWaveformTrials && ...
    design.PlannedLooks>=ceil(design.MaximumWaveformTrials/design.BatchSizeWaveformTrials) && ...
    design.TargetProbability>0 && design.TargetProbability<1 && ...
    design.CIWidthTarget>0 && design.CIWidthTarget<=1, ...
    'sixgr:phy:pdcch:InvalidMissedDetectionDesign','Invalid H1 probability, integer budget or planned looks.');
end
