classdef ConnectedDCIProfile
    % Configuration-owned single-cell/BWP 0_1/1_1 context, no legacy defaults.
    methods (Static)
        function validatePolicy(p)
            names={'spec_release','spec_version','configuration_epoch','serving_cell_index', ...
                'component_carrier_index','search_space_id','coreset_id','rnti_type','frequency_allocation_type','vrb_interleaving', ...
                'prb_bundling','rate_match_pattern_group_count','aperiodic_zp_csirs_resource_set_count', ...
                'harq_ack_codebook','supplementary_uplink','cross_carrier_scheduling','cbg_enabled', ...
                'csi_request_bits','beta_offsets','tci_present','additional_dci_features'};
            assert(isstruct(p) && isscalar(p) && all(isfield(p,names)) && ...
                isempty(setdiff(fieldnames(p),names)), ...
                'sixgr:phy:pdcch:IncompleteConnectedDCIPolicy','Connected DCI policy must explicitly declare every supported field, with no unknown keys.');
            assert(string(p.spec_release)=="Release-18" && string(p.spec_version)=="18.8.0" && ...
                string(p.rnti_type)=="C-RNTI" && string(p.frequency_allocation_type)=="type1_riv" && ...
                isequal(p.vrb_interleaving,false) && string(p.prb_bundling)=="staticBundling" && ...
                isequal(p.rate_match_pattern_group_count,0) && isequal(p.aperiodic_zp_csirs_resource_set_count,0) && ...
                string(p.harq_ack_codebook)=="dynamic" && isequal(p.supplementary_uplink,false) && ...
                isequal(p.cross_carrier_scheduling,false) && isequal(p.cbg_enabled,false) && ...
                isequal(p.csi_request_bits,0) && string(p.beta_offsets)=="semiStatic" && ...
                isempty(p.additional_dci_features) && islogical(p.tci_present) && isscalar(p.tci_present), ...
                'sixgr:phy:pdcch:UnsupportedConnectedDCIPolicy', ...
                'Connected DCI currently supports ordinary single-cell type-1 CP-OFDM with dynamic HARQ-ACK, static bundling/beta offsets and no optional extensions; unsupported features are not silently removed.');
            for name={'configuration_epoch','serving_cell_index','component_carrier_index'}
                validateattributes(p.(name{1}),{'double'},{'scalar','real','finite','integer','nonnegative'});
            end
            validateattributes(p.search_space_id,{'double'},{'scalar','integer','>=',0,'<=',39});
            validateattributes(p.coreset_id,{'double'},{'scalar','integer','>=',0,'<=',11});
        end

        function context=fromRuntimeConfig(cfg,format)
            control=cfg.phy.pdcch.operatorControl; p=control.connected_dci;
            sixgr.phy.pdcch.ConnectedDCIProfile.validatePolicy(p);
            fmt=sixgr.phy.pdcch.normalizeDCIFormat(format);
            formats=string(control.dci_formats(:).');
            assert(isequal(sort(formats),["0_1","1_1"]) && any(fmt==formats), ...
                'sixgr:phy:pdcch:UnsupportedConnectedDCIPolicy','This connected profile monitors the paired 0_1/1_1 formats.');
            dl=cfg.phy.bwp.dl; ul=cfg.phy.bwp.ul;
            assert(isscalar(cfg.phy.bwp.configuredDL) && isscalar(cfg.phy.bwp.configuredUL) && ...
                dl.NStartBWP==0 && ul.NStartBWP==0 && ...
                dl.NSizeBWP==cfg.phy.carrier.NSizeGrid && ul.NSizeBWP==cfg.phy.carrier.NSizeGrid, ...
                'sixgr:phy:pdcch:UnsupportedConnectedBWP', ...
                'The active scheduler profile requires one full-carrier BWP per direction; partial/multiple BWP scheduling must be integrated explicitly.');
            assert(cfg.phy.pdsch.RNTI==cfg.phy.pusch.RNTI && ~cfg.phy.pusch.transformPrecoding && ...
                cfg.phy.harq.nProcesses>=1 && cfg.phy.harq.nProcesses<=16, ...
                'sixgr:phy:pdcch:ConnectedRuntimeMismatch','Connected identity, CP-OFDM and ordinary HARQ process configuration disagree.');
            assert(~cfg.phy.harq.cbgEnabled && ...
                ~sixgr.util.structGet(cfg,'phy.pdsch.cbgTransmission',false) && ...
                ~sixgr.util.structGet(cfg,'phy.pusch.cbgTransmission',false) && ...
                ~sixgr.util.structGet(cfg,'phy.pusch.intraSlotFrequencyHopping',false) && ...
                ~sixgr.util.structGet(cfg,'phy.pusch.interSlotFrequencyHopping',false) && ...
                any(lower(string(sixgr.util.structGet(cfg,'phy.pusch.frequencyHopping.mode','neither')))==["neither","none","disabled"]) && ...
                any(lower(string(sixgr.util.structGet(cfg,'phy.pdsch.vrbToPRBMapping','noninterleaved')))==["noninterleaved","non_interleaved"]) && ...
                any(lower(string(sixgr.util.structGet(cfg,'phy.pdsch.prbBundlingType','static')))==["static","staticbundling"]), ...
                'sixgr:phy:pdcch:ConnectedRuntimeMismatch', ...
                'Runtime CBG, hopping, interleaving or bundling conflicts with the installed connected DCI policy.');
            dlRows=cfg.phy.pdsch.timeDomainAllocations; ulRows=cfg.phy.pusch.timeDomainAllocations;
            for rows={dlRows,ulRows}
                r=double(rows{1});
                assert(size(r,2)==4 && ~isempty(r) && size(r,1)<=16 && all(isfinite(r(:))) && ...
                    all(r(:)==fix(r(:))) && all(r(:,2)>=0 & r(:,3)>=1 & ...
                    r(:,2)+r(:,3)<=cfg.phy.numerology.symbolsPerSlot & r(:,4)>=0) && ...
                    isequal(r(:,1),(0:size(r,1)-1).'), ...
                    'sixgr:phy:pdcch:InvalidConnectedTDRA','TDRA requires contiguous zero-based row indices and explicit S/L/K0 or K2.');
            end
            feedback=double(cfg.phy.pucch.dlDataToULACK(:).');
            assert(~isempty(feedback) && numel(feedback)<=8 && all(isfinite(feedback)) && ...
                all(feedback==fix(feedback) & feedback>=0) && numel(unique(feedback))==numel(feedback), ...
                'sixgr:phy:pdcch:InvalidConnectedFeedbackList','dl-DataToUL-ACK must contain 1..8 distinct nonnegative integer offsets.');
            qcl=cfg.phy.pdsch.qclTCI;
            assert(~p.tci_present || (qcl.enabled && qcl.configuration_epoch==p.configuration_epoch), ...
                'sixgr:phy:pdcch:ConnectedTCIMismatch','TCI presence requires the installed same-epoch mapping.');
            data=struct('SpecRelease',string(p.spec_release),'SpecVersion',string(p.spec_version), ...
                'DCIFormat',fmt,'RNTIType',string(p.rnti_type),'RNTIValue',double(cfg.phy.pdsch.RNTI), ...
                'SearchSpaceType',"USS",'SearchSpaceID',double(cfg.phy.pdcch.searchSpace.id), ...
                'CORESETID',double(cfg.phy.pdcch.coreset.id), ...
                'ControlServingCell',p.serving_cell_index,'ControlCarrier',p.component_carrier_index, ...
                'ControlBWP',double(dl.BWPID),'ScheduledServingCell',p.serving_cell_index, ...
                'ScheduledCarrier',p.component_carrier_index,'ScheduledBWP',double(dl.BWPID), ...
                'InitialDLBWPSize',double(dl.NSizeBWP),'InitialDLBWPStart',double(dl.NStartBWP), ...
                'ActiveDLBWPSize',double(dl.NSizeBWP),'ActiveDLBWPStart',double(dl.NStartBWP), ...
                'InitialULBWPSize',double(ul.NSizeBWP),'InitialULBWPStart',double(ul.NStartBWP), ...
                'ActiveULBWPSize',double(ul.NSizeBWP),'ActiveULBWPStart',double(ul.NStartBWP), ...
                'FrequencyAllocationType',string(p.frequency_allocation_type), ...
                'DLTimeDomainAllocations',double(dlRows),'ULTimeDomainAllocations',double(ulRows), ...
                'CarrierIndicatorPresent',false,'CarrierIndicatorWidth',0,'CarrierIndicatorValue',0, ...
                'BWPIndicatorPresent',false,'BWPIndicatorWidth',0,'SULIndicatorPresent',false, ...
                'FrequencyHoppingEnabled',false,'TransformPrecodingEnabled',false, ...
                'HARQProcessCount',double(cfg.phy.harq.nProcesses),'DAIWidth',2, ...
                'AntennaPortFieldWidth',4,'LayerCapability',double(cfg.phy.mimo.maxRank),'TCIPresent',p.tci_present, ...
                'TCIWidth',3*double(p.tci_present),'ActiveTCIStateID',double(qcl.state_id), ...
                'SRSResourceIndicatorWidth',0,'SRSRequestWidth',2,'CSIRequestWidth',0, ...
                'RateMatchIndicatorWidth',0,'ZPCSIRSTriggerWidth',0,'CBGFieldsPresent',false, ...
                'CBGTransmissionWidth',0,'CBGFlushWidth',0,'DMRSSequenceInitializationPresent',true, ...
                'MonitoredFormats',formats,'ConfigurationEpoch',p.configuration_epoch, ...
                'ExecutionProfile',"configured_connected_dci_r18",'ResearchClass',"baseline_benchmark", ...
                'LegacyCompatibility',false,'ConnectedPolicy',p,'DLDataToULACK',feedback, ...
                'ULPrecoding',control.ul_precoding,'ULReferenceSignaling',control.ul_reference_signaling, ...
                'DLReferenceSignaling',control.dl_reference_signaling);
            % MCS bits have meaning only under the installed directional
            % tables. Bind both paired formats before accepting control,
            % not only later when constructing a data allocation.
            data.DLMCSTable=string(cfg.phy.pdsch.mcsTable);
            data.ULMCSTable=string(cfg.phy.pusch.mcsTable);
            experimentalUL=sixgr.phy.research.resolveExperimentalMCSTable(data.ULMCSTable);
            if ~isempty(experimentalUL)
                assert(isequaln(sixgr.util.structGet(cfg.phy.pusch,'experimentalMCSTable',[]),experimentalUL), ...
                    'sixgr:research:MCSTableContextMismatch','Reinstall changed experimental MCS contents explicitly.');
                data.ExperimentalULMCSTable=experimentalUL;
                data.ExperimentalULTransportPolicy=cfg.phy.pusch.researchTransportPolicy;
                data.ResearchClass=experimentalUL.ResearchClass;
            end
            if fmt=="0_1"
                data.ScheduledBWP=double(ul.BWPID);
                data.LayerCapability=double(control.ul_precoding.max_rank);
            end
            sixgr.phy.pdcch.ULPrecodingField.resolve(data);
            sixgr.phy.pdcch.ULReferenceSignaling.resolve(data);
            sixgr.phy.pdcch.DLReferenceSignaling.resolve(data);
            assert(data.ULPrecoding.max_rank==cfg.phy.pusch.maxLayers && ...
                cfg.phy.pusch.numLayers>=1 && cfg.phy.pusch.numLayers<=data.ULPrecoding.max_rank && ...
                (data.ULPrecoding.max_rank==1 || isequal(sixgr.util.structGet(cfg,'phy.pusch.enablePTRS',[]),false)) && ...
                data.ULReferenceSignaling.srs_resource_count==1 && ...
                cfg.phy.srs.nPorts==data.ULPrecoding.num_ports && ...
                cfg.phy.pusch.NumAntennaPorts==data.ULPrecoding.num_ports, ...
                'sixgr:phy:pdcch:ULPrecodingContextMismatch','SRS/PUSCH ports and selected rank must match the installed codebook. Multilayer connected operation requires PTRS disabled until its DCI association is integrated.');
            assert(any(string(control.search_space_type)==["ue","ue_specific","USS"]), ...
                'sixgr:phy:pdcch:ConnectedRuntimeMismatch','The connected profile requires UE-specific monitoring.');
            context=sixgr.phy.pdcch.DCIContext(data);
        end

        function schema=schema(context)
            d=context.Data; fmt=string(d.DCIFormat);
            sixgr.phy.pdcch.ConnectedDCIProfile.validatePolicy(d.ConnectedPolicy);
            isUL=fmt=="0_1";
            assert(isUL || fmt=="1_1",'sixgr:phy:pdcch:UnsupportedConnectedDCIPolicy','Connected format must be 0_1 or 1_1.');
            if isUL, n=d.ActiveULBWPSize; rows=d.ULTimeDomainAllocations;
            else, n=d.ActiveDLBWPSize; rows=d.DLTimeDomainAllocations; end
            f=ceil(log2(n*(n+1)/2)); t=ceil(log2(size(rows,1)));
            defs=[localDef('format_identifier',1,double(~isUL),double(~isUL)); ...
                localDef('frequency_resource_assignment',f,0,2^f-1); ...
                localDef('time_resource_assignment',t,0,size(rows,1)-1); ...
                localDef('mcs',5,0,31);localDef('ndi',1,0,1);localDef('rv',2,0,3); ...
                localDef('harq_process',4,0,d.HARQProcessCount-1)];
            if isUL
                prec=sixgr.phy.pdcch.ULPrecodingField.resolve(d);
                ref=sixgr.phy.pdcch.ULReferenceSignaling.resolve(d);
                defs=[defs;localDef('first_dai',2,0,3);localDef('tpc_command_for_pusch',2,0,3); ...
                    localDef('srs_resource_indicator',ref.SRIWidth,0,ref.SRIMaxValue); ...
                    localDef('precoding_information_and_number_of_layers',prec.Width,0,prec.MaxValue); ...
                    localDef('antenna_ports',ref.AntennaWidth,0,2^ref.AntennaWidth-1); ...
                    localDef('srs_request',2,0,0); ...
                    localDef('dmrs_sequence_initialization',1,0,1);localDef('ul_sch_indicator',1,1,1)];
            else
                ref=sixgr.phy.pdcch.DLReferenceSignaling.resolve(d);
                defs=[defs;localDef('dai',2,0,3);localDef('tpc_command_for_pucch',2,0,3); ...
                    localDef('pucch_resource_indicator',3,0,7); ...
                    localDef('pdsch_to_harq_feedback_timing',ceil(log2(numel(d.DLDataToULACK))),0,numel(d.DLDataToULACK)-1); ...
                    localDef('antenna_ports',ref.AntennaWidth,0,2^ref.AntennaWidth-1); ...
                    localDef('transmission_configuration_indication',d.TCIWidth,0,2^d.TCIWidth-1); ...
                    localDef('srs_request',2,0,0);localDef('dmrs_sequence_initialization',1,0,1)];
            end
            defs=defs(arrayfun(@(x)x.Width>0,defs));
            schema=struct('Format',fmt,'ContextDigest',context.Digest,'Definitions',defs, ...
                'RawBits',sum([defs.Width]),'FrequencyAssignmentBits',f,'TimeAssignmentBits',t, ...
                'SchemaVersion',"configured_connected_r18/v1",'StandardClause',"TS 38.212 V18.8.0 7.3.1.1.2/7.3.1.2.2");
        end

        function fields=scheduledFields(fields,context,cfg,grant,k1)
            d=context.Data; isUL=d.DCIFormat=="0_1";
            rows=d.DLTimeDomainAllocations; if isUL, rows=d.ULTimeDomainAllocations; end
            if size(rows,1)==1
                assert(fields.time_resource_assignment==0,'sixgr:phy:pdcch:InvalidConnectedTDRA','Single TDRA row has implicit index zero.');
                fields=rmfield(fields,'time_resource_assignment');
            end
            fields.srs_request=double(sixgr.util.structGet(grant,'SRSRequest',0));
            if isUL
                fields.first_dai=double(sixgr.util.structGet(grant,'DAI',1));
                fields.tpc_command_for_pusch=double(sixgr.util.structGet(grant,'TPCCommandForPUSCH',1));
                fields=sixgr.phy.pdcch.ULReferenceSignaling.bindSRI(fields,d, ...
                    double(sixgr.util.structGet(grant,'SRSResourceIndicator',0)));
                fields.precoding_information_and_number_of_layers= ...
                    sixgr.phy.pdcch.ULPrecodingField.encode(d,grant.NumLayers,grant.TPMI);
                fields.antenna_ports=sixgr.phy.pdcch.ULReferenceSignaling.antennaFromGrant(d,cfg,grant);
                fields.dmrs_sequence_initialization=double(cfg.phy.pusch.dmrs.NSCID);
                fields.ul_sch_indicator=1;
            else
                fields.dai=double(sixgr.util.structGet(grant,'DAI',1));
                fields.tpc_command_for_pucch=double(sixgr.util.structGet(grant,'TPC',1));
                fields.pucch_resource_indicator=double(sixgr.util.structGet(grant,'PUCCHResourceIndicator',0));
                index=find(d.DLDataToULACK==k1);
                assert(isscalar(index),'sixgr:phy:pdcch:FeedbackTimingNotConfigured','Scheduled K1 must occur in dl-DataToUL-ACK.');
                if numel(d.DLDataToULACK)>1, fields.pdsch_to_harq_feedback_timing=index-1; end
                fields.antenna_ports=sixgr.phy.pdcch.DLReferenceSignaling.antennaFromGrant(d,cfg,grant);
                if d.TCIPresent
                    qcl=cfg.phy.pdsch.qclTCI;
                    assert(grant.Slot-1>=qcl.activation_absolute_slot0 && qcl.configuration_epoch==d.ConfigurationEpoch, ...
                        'sixgr:qcl:InactiveTCI','DCI requires an active same-epoch TCI mapping.');
                    fields.transmission_configuration_indication=double(qcl.codepoint);
                end
                fields.dmrs_sequence_initialization=double(cfg.phy.pdsch.dmrs.NSCID);
            end
        end
    end
end

function value=localDef(name,width,minimum,maximum)
value=sixgr.phy.pdcch.DCIFieldDefinition(string(name),double(width),double(minimum),double(maximum), ...
    "installed_connected_RRC_configuration","TS 38.212 V18.8.0 7.3.1.1.2/7.3.1.2.2",false);
end
