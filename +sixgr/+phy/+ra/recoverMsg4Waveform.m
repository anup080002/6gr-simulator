function [pdcchRx, pdschRx, msg4] = recoverMsg4Waveform(rxWaveform, cfg, raCfg, sched, tx)
%RECOVERMSG4WAVEFORM Decode temp-C-RNTI PDCCH and Msg4 DL-SCH.
cfgRx = sixgr.phy.ra.localizeCarrierConfig(cfg, raCfg);
cfgRx = sixgr.phy.ra.localizeRAPDSCHConfig(cfgRx, sched.PDSCH);
cfgRx.phy.pdcch.rnti = double(raCfg.TempCRNTI);
cfgRx.phy.pdcch.KBits = double(raCfg.DCIPayloadBits);
cfgRx.phy.pdcch.dciPayloadBits = double(raCfg.DCIPayloadBits);
cfgRx.phy.pdcch.blindSearch = logical(sixgr.util.structGet(cfg, ...
    "phy.pdcch.blindSearch", false));
sixgr.config.assertRuntimeFeatureUse(cfgRx, "pdcch_blind_search", ...
    cfgRx.phy.pdcch.blindSearch, "recoverMsg4Waveform");
cfgRx.phy.pdcch.allowBlindCandidateTimingEstimate = false;
cfgRx.phy.pdcch.aggregationLevel = 4;
cfgRx.phy.pdcch.searchSpace.numCandidates = [0 0 1 0 0];
cfgRx = sixgr.phy.ra.localizeRAPDCCHConfig(cfgRx, tx.Carrier);
[pdcchRx, pdcchInfo] = sixgr.phy.dl.PDCCH_Rx(rxWaveform, cfgRx, ...
    "Carrier", tx.Carrier, "PDCCH", sixgr.util.structGet(sched, "PDCCH", []), ...
    "K", double(raCfg.DCIPayloadBits), ...
    "RNTI", double(raCfg.TempCRNTI), ...
    "ExpectedDCIBits", int8(sched.DCIBits(:)));
pdcchRx.Info = pdcchInfo;
if ~logical(sixgr.util.structGet(pdcchRx, "CausalGrantDecodeOk", false))
    pdschRx = struct("Ok", false, "CRCError", true);
    msg4 = struct();
    return;
end
controlEvent = sixgr.pdsch.RASIPDSCHContext.decodedControlEvent( ...
    pdcchRx, pdcchInfo, "msg4_contention_resolution", ...
    double(raCfg.TempCRNTI), "1_0", sched.DCIBits, ...
    "PDCCHAbsoluteSlot", double(raCfg.Msg4Slot), ...
    "EvidenceRole", "receiver_decode");
strict = sixgr.pdsch.RASIPDSCHContext.materialize( ...
    tx.Carrier, sched.PDSCH, controlEvent, ...
    localProcedureContext(cfgRx, raCfg, sched), ...
    "TransportBlockSize", double(tx.TransportBlockSize), ...
    "NPhysicalRxAntennas", size(rxWaveform, 2), ...
    "ChannelModel", localChannelModel(cfgRx), ...
    "MaxIterations", sixgr.phy.phycode.resolveLDPCMaxIterations( ...
        cfgRx, "Direction", "DL"));
[pdschRx, info] = sixgr.phy.dl.PDSCH_Rx(rxWaveform, cfgRx, ...
    "Carrier", tx.Carrier, ...
    "Assignment", strict.Assignment, ...
    "ResourcePlan", strict.ResourcePlan, ...
    "ReferenceSignalConfig", strict.ReferenceSignalConfig, ...
    "ReceiverConfig", strict.ReceiverConfig, ...
    "CodingPlan", strict.CodingPlans, ...
    "PrecoderBundle", strict.PrecoderBundle, ...
    "IntegrationContext", strict.IntegrationContext, ...
    "ExecutionProfile", "ra_si_strict");
pdschRx = sixgr.pdsch.RASIPDSCHContext. ...
    addCompatibilityEvidence(pdschRx);
pdschRx.Info = info;
pdschRx.PDCCHControlEvent = strict.ControlEvent;
if logical(pdschRx.Ok)
    payloadBits = int8(pdschRx.TransportBlock(1:double(tx.Msg4BitLength)));
    msg4 = sixgr.mac.ra.parseMsg4ContentionResolution(payloadBits);
else
    msg4 = struct();
end
end

function context = localProcedureContext(cfg, raCfg, sched)
context = struct( ...
    "Procedure", "msg4_contention_resolution", ...
    "RNTI", double(raCfg.TempCRNTI), ...
    "RNTIType", "TC-RNTI", ...
    "UEId", double(raCfg.UEId), ...
    "ServingCellId", double(raCfg.NCellID), ...
    "SchedulingCellId", double(raCfg.NCellID), ...
    "CCId", 0, "BWPId", 0, "ConfigurationEpoch", 0, ...
    "PDCCHAbsoluteSlot", double(raCfg.Msg4Slot), ...
    "PDSCHAbsoluteSlot", double(raCfg.Msg4Slot), ...
    "K0", 0, "MCSTable", "qam64", ...
    "MCSIndex", double(raCfg.Msg4PDSCH.MCS), ...
    "TargetCodeRate", double(sched.TargetCodeRate), ...
    "XOverhead", sixgr.phy.dl.resolvePDSCHXOverhead( ...
        cfg, sched.PDSCH.SymbolAllocation), ...
    "RV", double(sched.RV), "NDI", 1, ...
    "HARQProcessId", 0, "TCIStateId", 0, ...
    "ActiveBWPContextPresent", true, "EpochCurrent", true, ...
    "ServingCellActive", true, "MCSContextSupported", true, ...
    "TCIStateActive", true, "UECapability1024QAM", false, ...
    "RRCEnabled1024QAM", false, "DeploymentAllows1024QAM", false, ...
    "FrequencyRange", string(cfg.frequency.range_name), ...
    "OperatingBand", string(cfg.frequency.band_name), ...
    "DeploymentClass", "common_search_space_ra_si", ...
    "FrequencyRangeAllows1024QAM", false, ...
    "BandAllows1024QAM", false);
end

function model = localChannelModel(cfg)
model = upper(strtrim(string(sixgr.util.structGet( ...
    cfg, "channel.model", "AWGN"))));
if logical(sixgr.util.structGet(cfg, "channel.awgnOnly", false))
    model = "AWGN";
end
end
