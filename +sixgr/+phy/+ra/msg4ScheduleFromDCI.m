function sched = msg4ScheduleFromDCI(raCfg,bits,context)
% Materialize Msg4 solely from contextual DCI and common receiver rules.
dci = sixgr.phy.pdcch.DCIParser.parse(bits,context);
f = dci.Fields;
assert(context.Data.RNTIType=="TC-RNTI" && context.Data.RNTIValue==raCfg.TempCRNTI, ...
    'sixgr:phy:ra:Msg4DCIIdentityMismatch','Msg4 must use its received temporary C-RNTI.');
assert(f.vrb_to_prb_mapping==0,'sixgr:pdsch:UnsupportedMsg4Interleaving', ...
    'Interleaved Msg4 needs an implemented common VRB mapping.');
first = f.prb_start+f.reference_start-raCfg.NStartGrid;
assert(first>=0 && first+f.num_prb<=raCfg.NSizeGrid, ...
    'sixgr:phy:ra:Msg4AllocationOutsideCarrier','Decoded Msg4 allocation is outside the carrier.');
mcs = sixgr.pdsch.PDSCHMCSResolver.resolve("qam64",f.mcs, ...
    struct('NumCodewords',1,'RNTIType',"TC-RNTI",'SelectionSource',"tc_rnti_dci_bits"));
pdsch = nrPDSCHConfig;
pdsch.PRBSet = first+(0:f.num_prb-1);
pdsch.SymbolAllocation = [f.symbol_start f.num_symbols];
pdsch.MappingType = f.mapping_type;
pdsch.Modulation = mcs.Modulation; pdsch.NumLayers=1;
pdsch.RNTI=raCfg.TempCRNTI; pdsch.NID=raCfg.NCellID;
pdsch.DMRS.DMRSTypeAPosition=context.Data.DMRSTypeAPosition;
pdsch.DMRS.DMRSConfigurationType=1;
pdsch.DMRS.DMRSAdditionalPosition=2; pdsch.DMRS.DMRSLength=1;
pdsch.DMRS.NumCDMGroupsWithoutData=2;
if f.num_symbols==2, pdsch.DMRS.NumCDMGroupsWithoutData=1; end
pdsch.DMRS.NIDNSCID=raCfg.NCellID; pdsch.DMRS.NSCID=0;
pdsch.DMRS.DMRSPortSet=0; pdsch.EnablePTRS=false;
sched = struct('RNTI',raCfg.TempCRNTI,'DCIFormat',"1_0", ...
    'DCIBits',dci.Bits,'DCIContext',context,'DCIFieldTable',dci.FieldTable, ...
    'PDSCH',pdsch,'MCS',f.mcs,'MCSTable',"qam64",'Modulation',mcs.Modulation, ...
    'TargetCodeRate',mcs.TargetCodeRate,'RV',f.rv,'NDI',f.ndi, ...
    'HARQProcessId',f.harq_process,'TDRAIndex',f.time_resource_assignment, ...
    'TPCCommandForPUCCH',f.tpc_command_for_pucch, ...
    'PUCCHResourceIndicator',f.pucch_resource_indicator, ...
    'PDSCHToHARQFeedbackTimingIndicator',f.pdsch_to_harq_feedback_timing, ...
    'FeedbackTransmissionQualified',false);
end
