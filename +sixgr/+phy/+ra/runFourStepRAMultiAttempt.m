function result = runFourStepRAMultiAttempt(cfg, varargin)
%RUNFOURSTEPRAMULTIATTEMPT Execute bounded retries using the production chain.
%
% Attempts are independent waveform executions. AttemptId owns the power
% ramping counter; RATimingService owns the deterministic backoff boundary.

p = inputParser;
p.addParameter("RunFolder", "", @(x)ischar(x) || isstring(x));
p.addParameter("RunId", "ra_multi_attempt", ...
    @(x)ischar(x) || isstring(x));
p.addParameter("UEId", 1, @(x)isnumeric(x) && isscalar(x));
p.addParameter("AttemptFaults", strings(0, 1), ...
    @localTextVector);
p.addParameter("BackoffIndicatorMs", 0, ...
    @(x)isnumeric(x) && isscalar(x) && isfinite(x) && x >= 0);
p.addParameter("UniformDraws", 0, ...
    @(x)isnumeric(x) && isvector(x) && all(isfinite(x)));
p.addParameter("WriteArtifacts", false, ...
    @(x)islogical(x) || isnumeric(x));
p.parse(varargin{:});
opt = p.Results;

base = sixgr.mac.ra.RAConfig(cfg, ...
    "RunId", opt.RunId, "UEId", opt.UEId);
maxAttempts = round(double(base.PreambleTransMax));
faults = string(opt.AttemptFaults(:));
draws = double(opt.UniformDraws(:));
if isempty(draws)
    draws = 0;
end
runFolder = string(opt.RunFolder);
if strlength(strtrim(runFolder)) == 0
    runFolder = string(tempname);
end

attempts = cell(0, 1);
eventTables = cell(0, 1);
backoffRows = repmat(localBackoffRow(), 0, 1);
completed = false;
try
    numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
        double(base.CarrierSCSkHz), ...
        string(sixgr.util.structGet( ...
        cfg, "phy.carrier.CyclicPrefix", "normal")), ...
        "generic_waveform_test", "");
catch cause
    wrapped = MException("sixgr:phy:ia:InvalidRATimer", ...
        "Carrier SCS %g kHz does not resolve to an NR numerology.", ...
        double(base.CarrierSCSkHz));
    wrapped = addCause(wrapped, cause);
    throwAsCaller(wrapped);
end
for attemptIndex = 1:maxAttempts
    if attemptIndex <= numel(faults)
        fault = faults(attemptIndex);
    else
        fault = "none";
    end
    draw = draws(min(attemptIndex, numel(draws)));
    timing = sixgr.phy.ia.RATimingService.resolve( ...
        "NumerologyMu", double(numerology.Mu), ...
        "PRACHOccasionEndSlot", ...
            double(base.PRACHOccasionSlot), ...
        "RAResponseWindowSlots", ...
            double(base.RAResponseWindowSlots), ...
        "RARCompletionSlot", double(base.Msg2Slot), ...
        "Msg3CompletionSlot", double(base.Msg3Slot), ...
        "ContentionResolutionTimerSlots", ...
            double(base.RAContentionResolutionTimerSlots), ...
        "Msg4CompletionSlot", double(base.Msg4Slot), ...
        "BackoffIndicatorMs", double(opt.BackoffIndicatorMs), ...
        "UniformDraw0to1", draw);
    attemptFolder = fullfile(runFolder, ...
        "attempt_" + string(attemptIndex));
    attempt = sixgr.phy.ra.runFourStepRA(cfg, ...
        "RunFolder", attemptFolder, ...
        "RunId", string(opt.RunId) + "_A" + string(attemptIndex), ...
        "UEId", double(opt.UEId), ...
        "AttemptId", attemptIndex, ...
        "FaultMode", fault, ...
        "WriteArtifacts", logical(opt.WriteArtifacts), ...
        "RunNegativeSuite", false);
    attempts{end + 1, 1} = attempt; %#ok<AGROW>
    eventTables{end + 1, 1} = attempt.Events; %#ok<AGROW>
    backoffRows(end + 1, 1) = localBackoffRow( ...
        "AttemptID", string(attempt.RunId), ...
        "AttemptNumber", attemptIndex, ...
        "FaultMode", fault, ...
        "AppliedTxPower_dBm", ...
            double(attempt.PreambleTxPower_dBm), ...
        "BackoffSlots", double(timing.BackoffSlots), ...
        "RestartEarliestSlot", ...
            double(timing.RestartEarliestSlot), ...
        "Completed", logical(attempt.StrictOk), ...
        "FailureReason", string(attempt.FailureReason), ...
        "Status", string(ternary( ...
            logical(attempt.StrictOk), "PASS", "RETRY")));
    if logical(attempt.StrictOk)
        completed = true;
        break;
    end
end

if isempty(eventTables)
    events = table();
else
    events = vertcat(eventTables{:});
end
result = struct( ...
    "Completed", logical(completed), ...
    "AttemptsUsed", numel(attempts), ...
    "PreambleTransMax", maxAttempts, ...
    "AttemptResults", {attempts}, ...
    "Events", events, ...
    "AttemptSummary", struct2table(backoffRows, "AsArray", true), ...
    "PreambleTransMaxReached", ...
        ~completed && numel(attempts) == maxAttempts, ...
    "ProxyUsed", false, ...
    "FallbackUsed", false, ...
    "ExecutionBackend", "runFourStepRA_production_waveform");
end

function row = localBackoffRow(varargin)
row = struct( ...
    "AttemptID", "", "AttemptNumber", NaN, "FaultMode", "", ...
    "AppliedTxPower_dBm", NaN, "BackoffSlots", NaN, ...
    "RestartEarliestSlot", NaN, "Completed", false, ...
    "FailureReason", "", "Status", "");
for ii = 1:2:nargin
    row.(char(string(varargin{ii}))) = varargin{ii + 1};
end
end

function out = ternary(condition, a, b)
if condition
    out = a;
else
    out = b;
end
end

function tf = localTextVector(value)
tf = ischar(value) || isstring(value);
if iscell(value)
    tf = all(cellfun(@(item)ischar(item) || ...
        (isstring(item) && isscalar(item)), value(:)));
end
end
