function [projection, beamId, evidence] = resolveAssociatedSSBProjection(cfg, numElements)
% Physical common-DL TX mapping from the SSB actually associated with RACH.
% The projection uses the same matrix expansion as SSB_Tx/SSBBurstPlan.
associated = sixgr.util.structGet(cfg,'random_access.associated_ssb_index',NaN);
runtime = sixgr.util.structGet(cfg,'phy.ssb.runtimeSSBIndex',NaN);
source = string(sixgr.util.structGet(cfg,'random_access.associated_ssb_selection_source',""));
if ~(isnumeric(associated) && isscalar(associated) && isreal(associated) && ...
        isfinite(associated) && associated>=0 && associated==fix(associated) && ...
        isequal(associated,runtime) && isscalar(source) && ~ismissing(source) && ...
        strlength(strtrim(source))>0)
    error('sixgr:phy:ra:CommonDownlinkSSBAssociationMismatch', ...
        'Common DL runtime SSB must match the explicitly sourced RACH-associated SSB.');
end
validateattributes(numElements,{'numeric'},{'scalar','real','finite','integer','positive'});
selection = sixgr.phy.ia.SSBBurstPlan.selectedPrecoderFromConfig(cfg,associated);
if selection.NumTransmitAntennas~=numElements
    error('sixgr:phy:ra:StagePortProjectionDimensionMismatch', ...
        'Associated SSB uses %d elements, but the common DL transmitter has %d.', ...
        selection.NumTransmitAntennas,numElements);
end
projection = selection.MatrixRow.'; % Non-conjugating transpose: x*w_row.
beamId = selection.PrecoderID;
evidence = struct('SourceReferenceSignal',"SSB", ...
    'SourceReferenceSignalId',double(associated), ...
    'SelectionSource',source,'SSBPrecoderID',beamId, ...
    'SSBPrecoderMatrixSHA256',selection.PrecoderMatrixSHA256, ...
    'ProjectionMatrixSHA256',string(sixgr.phy.mimo.MatrixContract.digest(projection)), ...
    'Scope',"associated_ssb_common_downlink_tx_mapping_not_receiver_QCL_or_TCI_activation");
end
