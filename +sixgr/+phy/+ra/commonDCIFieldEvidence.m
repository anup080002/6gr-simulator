function T = commonDCIFieldEvidence(result,slot0,rnti,tx,rx,prefix)
%COMMONDCIFIELDEVIDENCE Executed TX and CRC-valid RX fields, never planned rows.
names={'RunId','UEId','AbsoluteSlot','RNTI','Endpoint','FieldName','WidthBits', ...
    'BitStart','BitEnd','Value','ContextDigest','ReferenceSource','EvidenceRole'};
types={'string','double','double','double','string','string','double','double', ...
    'double','double','string','string','string'};
T=table('Size',[0 numel(names)],'VariableTypes',types,'VariableNames',names);
observations={tx,rx}; endpoints=["gNB_TX","UE_RX"];
roles=["actual_transmitter_encoded_dci_fields","actual_crc_valid_decoded_dci_fields"];
for side=1:2
    obs=observations{side}; fields=sixgr.util.structGet(obs,prefix+"DCIFieldTable",table());
    if isempty(fields), continue; end
    % A later PDSCH CRC failure does not erase CRC-valid control evidence.
    if side==2 && ~logical(sixgr.util.structGet(obs,"PDCCHControlEvent.CRCPass",false)), continue; end
    n=height(fields);
    part=table(repmat(string(result.RunId),n,1),repmat(double(result.UEId),n,1), ...
        repmat(double(slot0),n,1),repmat(double(rnti),n,1), ...
        repmat(endpoints(side),n,1),string(fields.FieldName),fields.WidthBits, ...
        fields.BitStart,fields.BitEnd,fields.Value, ...
        repmat(string(obs.(prefix+'DCIContextDigest')),n,1), ...
        repmat(string(obs.(prefix+'DCIReferenceSource')),n,1),repmat(roles(side),n,1), ...
        'VariableNames',names);
    T=[T;part]; %#ok<AGROW>
end
end
