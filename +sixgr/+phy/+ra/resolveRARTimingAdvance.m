function timing = resolveRARTimingAdvance(command, firstULSCSkHz, sampleRateHz)
% TS 38.213 section 4.2: absolute RAR TA, not a relative MAC-CE command.
% N_TA = T_A * 16 * 64 / 2^mu, in the TS 38.211 basic time unit Tc.
% This excludes N_TA,offset and the UE received-DL clock origin. Those are
% separate absolute waveform scheduling inputs, not part of the RAR index.
if ~isnumeric(command) || ~isreal(command) || ~isscalar(command) || ...
        ~isfinite(command) || command~=fix(command) || command<0 || command>3846
    error('sixgr:phy:ra:InvalidRARTimingCommand','RAR TA must be an integer in [0,3846].');
end
validateattributes(sampleRateHz,{'numeric'},{'real','scalar','finite','positive'});
numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
    firstULSCSkHz,'normal','generic_waveform_test','');
stepTicks = 1024 / 2^double(numerology.Mu);
ticksPerSecond = double(sixgr.phy.frame.AbsoluteTime.TicksPerSecond);
ticks = double(command)*stepTicks;
timing = struct('Command',double(command),'FirstULSCSkHz',double(firstULSCSkHz), ...
    'Numerology',double(numerology.Mu),'StepTicks',stepTicks, ...
    'StepSeconds',stepTicks/ticksPerSecond, ...
    'StepSamples',stepTicks/ticksPerSecond*double(sampleRateHz), ...
    'NTA_Tc',ticks,'Seconds',ticks/ticksPerSecond, ...
    'Samples',ticks/ticksPerSecond*double(sampleRateHz), ...
    'SampleRateHz',double(sampleRateHz), ...
    'Standard','3GPP_TS_38.213_4.2_absolute_RAR_TA');
end
