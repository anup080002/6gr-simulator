function T = rarPDCCHCandidateEvidence(result, ra, info)
%RARPDCCHCANDIDATEEVIDENCE Actual blind decoder attempts, never a dummy row.
names={'RunId','CellId','UEId','AttemptId','CandidateIndex','AggregationLevel', ...
    'CCEIndex','RNTIAttempted','ExpectedRARNTI','CrcPass','DciFormatDecoded', ...
    'Metric','RejectedReason','IsSelectedCandidate','CandidateIndexWithinAggregation', ...
    'MetricDefinition','CCEIndexNAReason','EvidenceRole'};
types={'string','double','double','double','double','double','double','double', ...
    'double','logical','string','double','string','logical','double','string','string','string'};
T=table('Size',[0 numel(names)],'VariableTypes',types,'VariableNames',names);
C=sixgr.util.structGet(info,'CandidateResults',table());
if isempty(C), return; end
required={'CandidateIndex','AggregationLevel','CandidateIndexWithinAggregation', ...
    'DecodeAttempted','DecodeOK','ReceiverHestSINR_dB'};
if ~istable(C) || ~all(ismember(required,C.Properties.VariableNames)) || ...
        ~all(isfield(info,{'RNTI','SelectedCandidateIndex','HypothesisReductionClass'}))
    error('sixgr:phy:ra:IncompleteRARCandidateEvidence', ...
        'RAR candidate export requires actual decoder identities, CRC and selection evidence.');
end
C=C(logical(C.DecodeAttempted),:);
for k=1:height(C)
    passed=logical(C.DecodeOK(k));
    selected=passed && C.CandidateIndex(k)==info.SelectedCandidateIndex;
    format=""; reason="crc_fail";
    if passed
        format="1_0"; reason="";
        if ~selected, reason=string(info.HypothesisReductionClass)+"_unselected_hypothesis"; end
    end
    % Use the actual monitored CCE start. A candidate ordinal or a TX-side
    % allocation cannot replace a missing receiver identity.
    cce=NaN; cceReason="not_published_by_waveform_decoder";
    if ismember('CCEIndex',C.Properties.VariableNames)
        value=C.CCEIndex(k);
        assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
            (isnan(value) || (isfinite(value) && value>=0 && value==fix(value))), ...
            'sixgr:phy:ra:InvalidRARCandidateCCEIndex', ...
            'Receiver CCE start must be a nonnegative integer or explicitly unknown.');
        cce=double(value);
        if isfinite(cce), cceReason=""; end
    end
    T(k,:)={string(result.RunId),double(result.CellId),double(result.UEId), ...
        double(result.AttemptId),double(C.CandidateIndex(k)),double(C.AggregationLevel(k)), ...
        cce,double(info.RNTI),double(ra.RARNTI),passed,format, ...
        double(C.ReceiverHestSINR_dB(k)),reason,selected, ...
        double(C.CandidateIndexWithinAggregation(k)),"receiver_dmrs_hest_sinr_dB", ...
        cceReason,"actual_waveform_receiver_candidate_attempt"};
end
end
