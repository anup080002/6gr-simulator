function first=preparedStageTransmitStartSample(prepared)
% Actual queued RA waveform origin, not a nominal slot or RX search origin.
% DL producers have no UE timing-advance structure. UL producers must retain
% their received-clock/TA binding and agree with the same enqueue timestamp.
assert(isstruct(prepared) && isscalar(prepared) && ...
    all(isfield(prepared,{'Direction','StartTime_s','SampleRate_Hz'})), ...
    'sixgr:phy:ra:MissingPreparedTransmitClock', ...
    'Timing scoring and enqueue require the actual prepared TX sample clock.');
fs=double(prepared.SampleRate_Hz); start=double(prepared.StartTime_s);
assert(isscalar(fs) && isreal(fs) && isfinite(fs) && fs>0 && ...
    isscalar(start) && isreal(start) && isfinite(start) && start>=0, ...
    'sixgr:phy:ra:InvalidPreparedTransmitClock','Invalid prepared TX time or sample rate.');
first=start*fs;
assert(isfinite(first) && first<=flintmax && ...
    abs(first-round(first))<=8*eps(max(1,abs(first))), ...
    'sixgr:truth:SharedRAOriginOffClock','Prepared RA starts off the physical sample clock.');
first=round(first);
direction=string(prepared.Direction);
assert(isscalar(direction) && any(direction==["DL","UL"]), ...
    'sixgr:phy:ra:InvalidPreparedDirection','Prepared RA direction must be DL or UL.');
if direction=="UL"
    assert(isfield(prepared,'PhysicalTiming') && isstruct(prepared.PhysicalTiming) && ...
        isscalar(prepared.PhysicalTiming) && ...
        isfield(prepared.PhysicalTiming,'TransmitStartSample'), ...
        'sixgr:phy:ra:MissingSharedULTiming', ...
        'A shared UL producer must retain its received-clock/TA transmit origin.');
    bound=prepared.PhysicalTiming.TransmitStartSample;
    assert(isnumeric(bound) && isscalar(bound) && isreal(bound) && ...
        isfinite(bound) && double(bound)==first, ...
        'sixgr:phy:ra:SharedTransmitClockMismatch', ...
        'Queued TX samples must agree with the frozen UL physical timing.');
end
end
