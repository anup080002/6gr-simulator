function plan=planPRACHReceiveWindow(native,ordinal,receiver)
% Cell-owned receive geometry for one configured native PRACH hypothesis.
% No UE identity, selected SSB, preamble, prepared waveform, measured UE
% phase, injected delay or actual channel path is an input. The receiver
% observes a declared uncertainty interval whether or not a UE transmits.
% This planner neither arms the stream nor proves TDD/SSB RO validity. The
% cell calendar must authorize the native occasion before arming it, then
% pass actual received samples to the configured detector. Detector search
% retains all 64 preambles; CB partition admission is a separate decision.
required={'ContractVersion','FrequencyRange','PeriodFrames','PeriodPRACHSlots', ...
    'Occasions','ResolvedValid','FallbackUsed','UnknownIndexDefaulted'};
assert(isstruct(native) && isscalar(native) && all(isfield(native,required)) && ...
    string(native.ContractVersion)=="sixgr_prach_occasion_release18/v1" && ...
    isequal(native.ResolvedValid,true) && isequal(native.FallbackUsed,false) && ...
    isequal(native.UnknownIndexDefaulted,false), ...
    'sixgr:phy:ra:PRACHReceiveNativeRequired','Retain the original configured native occasion resolution.');
rows=native.Occasions;
fields=["Ordinal","PRACHSlot","FrequencyIndex","RARNTISymbolIndex","RARNTISlotIndex", ...
    "PRACHWaveformStartTicks","PRACHWaveformEndTicksExclusive", ...
    "PRACHActiveStartTicks","PRACHActiveEndTicksExclusive"];
assert(istable(rows) && height(rows)>0 && all(ismember(fields,string(rows.Properties.VariableNames))), ...
    'sixgr:phy:ra:PRACHReceiveNativeRequired','Native CP/useful and full waveform support must be retained.');
integer(ordinal,1); integer(native.PeriodFrames,1); integer(native.PeriodPRACHSlots,1);
assert(isequal(double(rows.Ordinal),(1:height(rows)).'), ...
    'sixgr:phy:ra:PRACHReceiveNativeRequired','Original native row ordinals must be complete and ordered.');
names={'CellID','ConfigurationEpoch','SampleRateHz','RadioFrameZeroSample', ...
    'ConfigurationAvailableAtSample','TimingAdvanceOffsetPresent','TimingAdvanceOffset', ...
    'SearchGuardSamples','FilterTailSamples','NumReceiveAntennas','ULCarrierID'};
assert(isstruct(receiver) && isscalar(receiver) && all(isfield(receiver,names)), ...
    'sixgr:phy:ra:PRACHReceiveClockRequired','Use the independent configured cell clock and receiver uncertainty.');
% Reject accidental substitution of the UE-prepared timing contract.
assert(~any(isfield(receiver,{'DLReference','ReceivedRARTiming','TransmitStartSample','PreambleIndex','SelectedSSBIndex'})), ...
    'sixgr:phy:ra:PRACHReceiveUEAuthorityForbidden','A cell monitor must not depend on UE-selected/received/prepared state.');
for name=["CellID","ConfigurationEpoch","RadioFrameZeroSample","ConfigurationAvailableAtSample", ...
        "SearchGuardSamples","FilterTailSamples","ULCarrierID"]
    integer(receiver.(name),0);
end
integer(receiver.NumReceiveAntennas,1);
assert(any(receiver.ULCarrierID==[0 1]),'sixgr:phy:ra:PRACHReceiveClockRequired','UL carrier ID must be 0 or 1.');
validateattributes(receiver.SampleRateHz,{'numeric'},{'scalar','real','finite','positive'});
tc=double(sixgr.phy.frame.AbsoluteTime.TicksPerSecond)/double(receiver.SampleRateHz);
assert(tc==fix(tc) && tc>=1,'sixgr:phy:ra:PRACHReceiveClockNotExact','The receiver clock must map exactly to Tc.');
offset=sixgr.phy.frame.resolveULTimingAdvanceOffsetValue( ...
    receiver.TimingAdvanceOffsetPresent,receiver.TimingAdvanceOffset,native.FrequencyRange);
assert(rem(offset.NTAOffset_Tc,int64(tc))==0, ...
    'sixgr:phy:ra:PRACHReceiveClockNotExact','Do not round the configured common timing offset.');
periodIndex=floor((double(ordinal)-1)/height(rows)); rowIndex=mod(double(ordinal)-1,height(rows))+1;
row=rows(rowIndex,:);
periodTicks=double(native.PeriodFrames)*double(sixgr.phy.frame.AbsoluteTime.TicksPerFrame);
translation=periodIndex*periodTicks;
assert(isfinite(translation) && translation<=flintmax && translation==fix(translation), ...
    'sixgr:phy:ra:PRACHReceiveClockNotExact','The repeated native occasion must remain exactly representable.');
ticks=zeros(1,4,'int64');
timeNames=fields(end-3:end);
for k=1:4
    x=row.(timeNames(k));
    assert(isa(x,'int64') && isscalar(x) && x>=0 && double(x)+translation<=flintmax, ...
        'sixgr:phy:ra:PRACHReceiveNativeRequired','Retain original exact native support, not inferred slot durations.');
    ticks(k)=x+int64(translation);
end
assert(ticks(1)<=ticks(3) && ticks(3)<ticks(4) && ticks(4)<=ticks(2), ...
    'sixgr:phy:ra:PRACHReceiveNativeRequired','CP/useful support must lie inside the native waveform extent.');
assert(all(rem(ticks,int64(tc))==0),'sixgr:phy:ra:PRACHReceiveClockNotExact', ...
    'Native support must lie on the actual receiver sample clock; no rounded capture boundaries.');
samples=double(ticks)/tc+double(receiver.RadioFrameZeroSample);
advance=double(offset.NTAOffset_Tc)/tc;
center=samples(1)-advance;
first=center-double(receiver.SearchGuardSamples);
last=samples(2)-advance+double(receiver.SearchGuardSamples)+double(receiver.FilterTailSamples);
assert(all(isfinite([samples first last])) && all(abs([samples first last])<=flintmax) && ...
    first>=0 && last>first,'sixgr:phy:ra:PRACHReceiveClockNotExact','Receive window exceeds the retained physical clock.');
assert(receiver.ConfigurationAvailableAtSample<=first, ...
    'sixgr:phy:ra:PRACHReceiveConfigurationTooLate','The gNB configuration must be installed before receive monitoring starts.');
rarnti=sixgr.phy.ra.computeRARNTI('SymbolIndex',row.RARNTISymbolIndex, ...
    'SlotIndex',row.RARNTISlotIndex,'FrequencyIndex',row.FrequencyIndex, ...
    'ULCarrierId',receiver.ULCarrierID);
plan=struct('ContractVersion',"cell_PRACH_receive_window/v1", ...
    'Source',"configured_cell_native_PRACH_clock_and_receiver_search_budget", ...
    'Scope',"receive_geometry_not_RO_validity_arming_or_detection", ...
    'CellID',double(receiver.CellID),'ConfigurationEpoch',double(receiver.ConfigurationEpoch), ...
    'NativeResolutionSHA256',string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(native)))), ...
    'OriginalNativeRow',row,'NativePeriodIndex0',periodIndex, ...
    'OccasionOrdinal1',double(ordinal), ...
    'PRACHSlotIndex0',double(row.PRACHSlot)+periodIndex*double(native.PeriodPRACHSlots), ...
    'FrequencyIndex0',double(row.FrequencyIndex),'ExpectedRARNTI',rarnti, ...
    'CandidatePreambles0',0:63,'SampleRateHz',double(receiver.SampleRateHz), ...
    'RadioFrameZeroSample',double(receiver.RadioFrameZeroSample), ...
    'NominalWaveformStartSample',samples(1),'NominalWaveformEndSampleExclusive',samples(2), ...
    'NativeActiveStartTicks',ticks(3),'NativeActiveEndTicksExclusive',ticks(4), ...
    'ReceiverPRACHSlotOriginSample',center,'ReceiveStartSample',first, ...
    'ReceiveEndSampleExclusive',last,'DetectorInputStartOffsetSamples',double(receiver.SearchGuardSamples), ...
    'SearchGuardSamples',double(receiver.SearchGuardSamples),'FilterTailSamples',double(receiver.FilterTailSamples), ...
    'NumReceiveAntennas',double(receiver.NumReceiveAntennas), ...
    'CommonOffset',offset,'ConfigurationAvailableAtSample',double(receiver.ConfigurationAvailableAtSample), ...
    'UETransmissionRequired',false,'WaveformExecuted',false,'ReceiverArmed',false);
end

function integer(x,minimum)
assert(isnumeric(x) && ~islogical(x) && isreal(x) && isscalar(x) && isfinite(x) && ...
    x==fix(x) && x>=minimum && x<=flintmax,'sixgr:phy:ra:PRACHReceiveClockRequired', ...
    'Clock and identity operands must be exact original integers.');
end
