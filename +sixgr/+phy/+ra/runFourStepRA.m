end

function val = localFirstFiniteScalar(varargin)
val = NaN;
for i = 1:nargin
    raw = varargin{i};
    if isempty(raw)
        continue;
    end
    vals = double(raw(:));
    vals = vals(isfinite(vals));
    if ~isempty(vals)
        val = vals(1);
        return;
    end
end
end

function [val, source] = localFirstFiniteScalarWithSource(varargin)
val = NaN;
source = "unavailable";
for i = 1:2:nargin
    label = string(varargin{i});
