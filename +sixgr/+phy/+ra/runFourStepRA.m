function [result, continuation] = runFourStepRA(cfg, varargin)
%RUNFOURSTEPRA Execute an NR-style contention-based four-step RA anchor.
%
% The receiver side consumes only decoded runtime evidence: PRACH waveform
% correlation, RA-RNTI PDCCH, RAR PDSCH bytes, RAR UL grant, Msg3 PUSCH, and
% Msg4 PDSCH contention identity.
% StopAfterStage returns a continuation after the selected decoded stage.
% Resuming consumes that state; it does not rerun completed PHY stages.
% StageAction=prepare_next_stage returns generated TX samples without
% propagation or receiver evidence. Resume with execute to receive them.
% RuntimeSlot is the one-based scheduler slot at which a new attempt starts.
% ReceiveThroughTime_s bounds stage reception on the absolute runtime clock.
% A stage whose complete sample interval is not due remains prepared.
% RuntimeStageWaveforms can supply a WaveformObservationBuffer per stage:
% its rate, absolute origin and received coverage must match the preparation.
% Such completion does not propagate samples or advance channel/RF state.
% This is a stage boundary API, not yet a per-sample/slot waveform scheduler.

sixgr.runtime.RuntimeCallLedger.record("sixgr.phy.ra.runFourStepRA", ...
    "INITIAL_ACCESS", "BIDIRECTIONAL", struct("Stage","FOUR_STEP_RA"));

p = inputParser;
p.addParameter("RunFolder", "", @(x)ischar(x) || isstring(x));
p.addParameter("RunId", "ra_anchor", @(x)ischar(x) || isstring(x));
p.addParameter("ScenarioName", "", @(x)ischar(x) || isstring(x));
p.addParameter("UEId", 1, @(x)isnumeric(x) && isscalar(x));
p.addParameter("CellId", [], @(x)isempty(x) || (isnumeric(x) && isscalar(x)));
p.addParameter("AttemptId", 1, @(x)isnumeric(x) && isscalar(x));
p.addParameter("FaultMode", "none", @(x)ischar(x) || isstring(x));
p.addParameter("WriteArtifacts", true, @(x)islogical(x) || isnumeric(x));
p.addParameter("RunNegativeSuite", false, @(x)islogical(x) || isnumeric(x));
p.addParameter("SIB1Recovery", struct(), @(x) isempty(x) || isstruct(x));
p.addParameter("RequireDecodedSIB1", false, @(x)islogical(x) || isnumeric(x));
p.addParameter("RuntimeIntegrationMode", "standalone_self_loop", @(x)ischar(x) || isstring(x));
p.addParameter("RuntimeStageWaveforms", struct(), @(x) isempty(x) || isstruct(x));
p.addParameter("RequireRuntimeStageWaveforms", false, @(x)islogical(x) || isnumeric(x));
p.addParameter("AllowRuntimeStageWaveformComposition", false, @(x)islogical(x) || isnumeric(x));
p.addParameter("UseRuntimeChannel", false, @(x)islogical(x) || isnumeric(x));
p.addParameter("RuntimeNoiseSNR_dB", Inf, @(x)isnumeric(x) && isscalar(x));
p.addParameter("RuntimeSlot", NaN, @(x)isnumeric(x) && isscalar(x));
p.addParameter("InitialDLChannelState", struct(), @(x)isempty(x) || isstruct(x));
p.addParameter("InitialULChannelState", struct(), @(x)isempty(x) || isstruct(x));
p.addParameter("StopAfterStage", "complete_attempt", @(x)(ischar(x) || isstring(x)) && isscalar(string(x)));
p.addParameter("Continuation", struct(), @(x)isstruct(x) && isscalar(x));
p.addParameter("StageAction", "execute", @(x)(ischar(x) || isstring(x)) && isscalar(string(x)));
p.addParameter("ReceiveThroughTime_s", Inf, @(x)isnumeric(x) && isreal(x) && ...
    isscalar(x) && ~isnan(x) && x >= 0);
p.parse(varargin{:});
opt = p.Results;
prepareOnly = strcmpi(string(opt.StageAction), "prepare_next_stage");
if ~prepareOnly && ~strcmpi(string(opt.StageAction), "execute")
    error("sixgr:phy:ra:InvalidRAStageAction", "StageAction must be execute or prepare_next_stage.");
end
continuation = struct();
stageNames = ["Msg1", "Msg2", "Msg3", "Msg4", "RRCSetupComplete"];
stopStage = find(strcmpi(string(opt.StopAfterStage), stageNames), 1);
if strcmpi(string(opt.StopAfterStage), "complete_attempt")
    stopStage = 5;
elseif isempty(stopStage)
    error("sixgr:phy:ra:InvalidRAStageBoundary", ...
        "StopAfterStage must name Msg1, Msg2, Msg3, Msg4, RRCSetupComplete, or complete_attempt.");
end
if (stopStage < 5 || prepareOnly || isfinite(opt.ReceiveThroughTime_s)) && nargout < 2
    error("sixgr:phy:ra:MissingRAContinuationOutput", ...
        "A stopped RA attempt requires the second output to retain its receiver-owned continuation.");
end
inputConfig = cfg;
nextStage = 1;
reusePreparedStage = 0;
if ~isempty(fieldnames(opt.Continuation))
    saved = opt.Continuation;
    required = ["ContractVersion", "InputConfig", "Config", "Options", "NextStage", ...
        "Result", "RAConfig", "Timing", "Runtime", "PowerState", "Events", "OracleRows", "TimerRows", ...
        "Msg1Tx", "Detection", "TimingAdvance", "Msg2Tx", "PDCCHInfo", "PDSCHRx2", "RARRx", ...
        "GrantRx", "Msg3Tx", "Msg3Rx", "Msg3Decoded", "UEIdentity", "Msg4Tx", ...
        "ResumePhase", "PreparedContext"];
    if ~all(isfield(saved, required)) || saved.ContractVersion ~= "ra_stage_continuation_v3" || ...
            ~isscalar(saved.NextStage) || ~ismember(saved.NextStage, 1:5) || ...
            ~isscalar(saved.ResumePhase) || ~any(saved.ResumePhase == ["decoded", "prepared"]) || ...
            (saved.NextStage == 1 && saved.ResumePhase ~= "prepared")
        error("sixgr:phy:ra:InvalidRAContinuation", "Invalid decoded-stage RA continuation contract.");
    end
    if ~isequaln(cfg, saved.InputConfig)
        error("sixgr:phy:ra:RAContinuationConfigChanged", ...
            "The attempt's validated configuration cannot change while resuming its decoded state.");
    end
    if stopStage < saved.NextStage
        error("sixgr:phy:ra:RAStageAlreadyExecuted", ...
            "The requested stage was already executed; the next stage is %s.", stageNames(saved.NextStage));
    end
    dynamicOptions = ["Continuation", "StopAfterStage", "StageAction", "InitialDLChannelState", ...
        "InitialULChannelState", "RuntimeStageWaveforms", "RuntimeSlot", "ReceiveThroughTime_s"];
    for name = setdiff(string(p.Parameters), [string(p.UsingDefaults), dynamicOptions])
        if ~isequaln(opt.(name), saved.Options.(name))
            error("sixgr:phy:ra:RAContinuationOptionChanged", ...
                "Attempt option %s changed across a decoded-stage continuation.", name);
        end
    end
    supplied = opt;
    opt = saved.Options;
    if ~isfield(opt, "ReceiveThroughTime_s")
        opt.ReceiveThroughTime_s = Inf; % Older checkpoints are unbounded offline attempts.
    end
    if ~ismember("ReceiveThroughTime_s", string(p.UsingDefaults))
        if isfinite(opt.ReceiveThroughTime_s) && supplied.ReceiveThroughTime_s < opt.ReceiveThroughTime_s
            error("sixgr:phy:ra:RAReceiveClockMovedBackward", ...
                "ReceiveThroughTime_s cannot move backward across a continuation.");
        end
        opt.ReceiveThroughTime_s = supplied.ReceiveThroughTime_s;
    end
    if isfinite(opt.ReceiveThroughTime_s) && nargout < 2
        error("sixgr:phy:ra:MissingRAContinuationOutput", ...
            "A receive-time-bounded RA attempt requires its continuation output.");
    end
    cfg = saved.Config;
    nextStage = saved.NextStage;
    result = saved.Result;
    raCfg = saved.RAConfig;
    raTiming = saved.Timing;
    runtime = saved.Runtime;
    for direction = ["DL", "UL"]
        optionName = "Initial" + direction + "ChannelState";
        if ~ismember(optionName, string(p.UsingDefaults))
            runtime.(direction + "ChannelState") = localResumeChannelState( ...
                runtime.(direction + "ChannelState"), supplied.(optionName));
        end
    end
    if ~ismember("RuntimeStageWaveforms", string(p.UsingDefaults))
        runtime.StageWaveforms = supplied.RuntimeStageWaveforms;
    end
    if ~ismember("RuntimeSlot", string(p.UsingDefaults))
        opt.RuntimeSlot = supplied.RuntimeSlot;
        runtime.RuntimeSlot = supplied.RuntimeSlot;
    end
    powerState = saved.PowerState;
    events = saved.Events;
    oracleRows = saved.OracleRows;
    timerRows = saved.TimerRows;
    msg1Tx = saved.Msg1Tx; det = saved.Detection; ta = saved.TimingAdvance;
    msg2Tx = saved.Msg2Tx; pdcchInfo = saved.PDCCHInfo;
    pdschRx2 = saved.PDSCHRx2; rarRx = saved.RARRx; grantRx = saved.GrantRx;
    msg3Tx = saved.Msg3Tx; msg3Rx = saved.Msg3Rx; msg3Decoded = saved.Msg3Decoded;
    ueIdentity = saved.UEIdentity; msg4Tx = saved.Msg4Tx;
    if saved.ResumePhase == "prepared"
        reusePreparedStage = nextStage;
        prepared = saved.PreparedContext;
        switch nextStage
            case 1
                occasion = prepared.Occasion;
            case 2
                msg2Sched = prepared.Msg2Schedule;
                withinWindow = prepared.WithinWindow;
                attemptedRNTI = prepared.AttemptedRNTI;
                rarTx = prepared.RARTx;
            case 3
                msg3TxPayload = prepared.Msg3Payload;
                pusch = prepared.PUSCH;
                msg3TA = prepared.TimingAdvanceWaveform;
            case 4
                msg4Sched = prepared.Msg4Schedule;
                msg4TxPayload = prepared.Msg4Payload;
            case 5
                setupCompleteTx = prepared.Tx;
                setupCompleteTxPayload = prepared.Payload;
                setupCompletePUSCH = prepared.PUSCH;
                setupCompleteTA = prepared.TimingAdvanceWaveform;
        end
    end
    faultMode = lower(strtrim(string(opt.FaultMode)));
else
opt = rmfield(opt, "Continuation");
localProgress(opt, "start", "runFourStepRA entered");

localRequireToolboxFunctions();
localProgress(opt, "toolbox_checked", "required toolbox functions are available");
[cfg, sib1BindingEvidence] = localApplyDecodedSIB1IfPresent(cfg, opt.SIB1Recovery);
if logical(opt.RequireDecodedSIB1) && (~istable(sib1BindingEvidence) || height(sib1BindingEvidence) == 0)
    error("sixgr:mac:ra:UE_RACH_CONFIG_ORACLE_READ", ...
        "UE_RACH_CONFIG_ORACLE_READ: Phase 4 four-step RA requires receiver-owned RACH configuration from decoded SIB1; YAML-owned random_access is not allowed.");
end
raCfg = sixgr.mac.ra.RAConfig(cfg, ...
    "RunId", opt.RunId, ...
    "ScenarioName", opt.ScenarioName, ...
    "UEId", opt.UEId, ...
    "CellId", opt.CellId, ...
    "AttemptId", opt.AttemptId, ...
    "RuntimeSlot", opt.RuntimeSlot);
localProgress(opt, "ra_config_resolved", sprintf("ue=%g cell=%s preamble=%g", ...
    double(opt.UEId), localDisplayScalar(opt.CellId), double(raCfg.PreambleIndex)));
cfg = sixgr.phy.ra.localizeCarrierConfig(cfg, raCfg);
try
    numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
        double(raCfg.CarrierSCSkHz), ...
        string(sixgr.util.structGet( ...
        cfg, "phy.carrier.CyclicPrefix", "normal")), ...
        "generic_waveform_test", "");
catch cause
    wrapped = MException("sixgr:phy:ia:InvalidRATimer", ...
        "Carrier SCS %g kHz does not resolve to an NR numerology.", ...
        double(raCfg.CarrierSCSkHz));
    wrapped = addCause(wrapped, cause);
    throwAsCaller(wrapped);
end
mu = double(numerology.Mu);
raTiming = sixgr.phy.ia.RATimingService.resolve( ...
    "NumerologyMu", mu, ...
    "PRACHOccasionEndSlot", double(raCfg.PRACHOccasionEndSlot), ...
    "RAResponseWindowSlots", double(raCfg.RAResponseWindowSlots), ...
    "RARCompletionSlot", double(raCfg.Msg2Slot), ...
    "Msg3CompletionSlot", double(raCfg.Msg3Slot), ...
    "ContentionResolutionTimerSlots", ...
        double(raCfg.RAContentionResolutionTimerSlots), ...
    "Msg4CompletionSlot", double(raCfg.Msg4Slot), ...
    "BackoffIndicatorMs", 0, ...
    "UniformDraw0to1", 0);
faultMode = lower(strtrim(string(opt.FaultMode)));
runFolder = string(opt.RunFolder);
if strlength(strtrim(runFolder)) == 0
    runFolder = string(tempname);
end

result = localEmptyResult(raCfg, runFolder, faultMode);
result.AssociatedSSBIndex = double(sixgr.util.structGet(cfg, ...
    "random_access.associated_ssb_index", NaN));
result.AssociatedSSBSelectionSource = string(sixgr.util.structGet(cfg, ...
    "random_access.associated_ssb_selection_source", ""));
result.AssociatedSSBMeasurement_dB = double(sixgr.util.structGet(cfg, ...
    "random_access.associated_ssb_measurement_db", NaN));
result.Msg1BeamPolicy = string(sixgr.util.structGet(cfg, ...
    "random_access.msg1_beam_policy", ""));
result.SSBToPRACHAssociationApplied = isfinite(result.AssociatedSSBIndex) && ...
    strlength(strtrim(result.AssociatedSSBSelectionSource)) > 0;
result.RAResponseWindowStartSlot = ...
    double(raTiming.ResponseWindowStartSlot);
result.RAResponseWindowEndSlot = ...
    double(raTiming.ResponseWindowLastSlot);
result.ContentionResolutionExpirySlotExclusive = ...
    double(raTiming.ContentionExpirySlotExclusive);
localProgress(opt, "runtime_transport_resolve_start", "");
runtime = localResolveRuntimeTransport(cfg, raCfg, opt);
localProgress(opt, "runtime_transport_resolve_done", string(runtime.Mode));
result = localApplyRuntimeTransportToResult(result, runtime);
result.SIB1RACHBindingEvidence = sib1BindingEvidence;
result.SIB1RACHBindingApplied = istable(sib1BindingEvidence) && height(sib1BindingEvidence) > 0;
if logical(result.SIB1RACHBindingApplied)
    result.SIB1RACHBindingSource = "decoded_sib1_rach_config_common";
    result.SIB1RACHPayloadHash = string(sib1BindingEvidence.PayloadHash(1));
    result.SIB1RACHTreeHash = string(sib1BindingEvidence.TreeHash(1));
end
powerState = localResolveRATransmitPower(cfg, raCfg);
result = localApplyPowerStateToResult(result, powerState);
events = localInitialEvents(raCfg);
oracleRows = localOracleGuardRows(raCfg);
timerRows = localTimerRowsStart(raCfg);
msg1Tx = struct(); det = struct(); ta = struct(); msg2Tx = struct();
pdcchInfo = struct(); pdschRx2 = struct(); rarRx = struct(); grantRx = struct();
msg3Tx = struct(); msg3Rx = struct(); msg3Decoded = struct();
ueIdentity = ""; msg4Tx = struct();
end
result.RuntimeExecutionState = "executing";
result.NextRuntimeStage = "";
result.NextRuntimeStageSlot = NaN;
result.PreparedTransmission = struct();

try
    if nextStage <= 1
    if reusePreparedStage ~= 1
    localProgress(opt, "msg1_tx_start", "");
    [msg1Tx, occasion] = sixgr.phy.ra.generateMsg1PRACHWaveform(cfg, raCfg);
    localProgress(opt, "msg1_tx_done", sprintf("samples=%d", size(msg1Tx.Waveform, 1)));
    [msg1Tx.Waveform, msg1Power] = localApplyWaveformTxPower(msg1Tx.Waveform, ...
        powerState.PreambleTxPower_dBm, powerState.ReferenceTxPower_dBm);
    msg1Tx.PowerControl = powerState;
    msg1Tx.PowerControl.PreambleTxAmplitudeScale = double(msg1Power.AmplitudeScale);
    result.PreambleTxAmplitudeScale = double(msg1Power.AmplitudeScale);
    end
    if prepareOnly || ~localStageReceiveReady(cfg, raCfg, "Msg1", msg1Tx.Waveform, msg1Tx, opt, runtime.StageWaveforms)
        [result, continuation] = captureContinuation(1, struct("Occasion", occasion), ...
            msg1Tx.Waveform, msg1Tx, "UL");
        return;
    end
    localProgress(opt, "msg1_channel_start", "");
    [msg1RxWave, runtime, stageInfo] = localResolveStageRxWaveform("Msg1", "UL", msg1Tx.Waveform, cfg, raCfg, msg1Tx, runtime);
    localProgress(opt, "msg1_channel_done", "");
    result = localAppendRuntimeStage(result, stageInfo, runtime);
    if faultMode == "no_prach_detected"
        msg1RxWave(:) = 0;
    end
    localProgress(opt, "msg1_detect_start", "");
    cfgMsg1Rx = localApplyRuntimeReceiverSyncContext(cfg, runtime, "UL");
    det = sixgr.phy.ra.detectMsg1PRACH(msg1RxWave, cfgMsg1Rx, raCfg, occasion);
    det = localAttachMsg1ReferenceEvidence(det, stageInfo);
    localProgress(opt, "msg1_detect_done", sprintf("detected=%d", logical(det.Detected)));
    if isfield(det, "CorrelationTrace")
        result.Msg1DetectionTrace = det.CorrelationTrace;
    end
    ta = sixgr.phy.ra.estimateTimingAdvanceFromPRACH( ...
        det,msg1Tx.SampleRate_Hz,raCfg.CarrierSCSkHz);
    detectorAmbiguity = logical(sixgr.util.structGet(det, "MultiCandidateAboveThreshold", false));
    collisionDetected = faultMode == "collision_same_preamble";
    preambleDetected = logical(det.Detected) && double(det.DetectedPreambleIndex) == double(raCfg.PreambleIndex) && ~collisionDetected;
    result = localApplyMsg1(result, raCfg, det, ta, collisionDetected, preambleDetected, detectorAmbiguity);
    events = [events; localEvent(raCfg, "MSG1_PRACH_TX", ternary(preambleDetected, "MSG1_PRACH_DETECTED", "RA_FAILURE"), ...
        "prach_correlation_detection", "", NaN, double(raCfg.RARNTI), double(raCfg.PreambleIndex), ...
        ternary(preambleDetected, "", localFailureForMsg1(collisionDetected)))]; %#ok<AGROW>
    if ~preambleDetected
        result = localFail(result, localFailureForMsg1(collisionDetected), "MSG1_PRACH_DETECTED");
        result = localFinalize(result, raCfg, events, timerRows, oracleRows, msg1Tx, det, struct(), struct(), struct(), struct(), struct(), struct(), struct(), opt);
        return;
    end

    if stopStage == 1
        [result, continuation] = captureContinuation(2);
        return;
    end
    end

    if nextStage <= 2
    if reusePreparedStage ~= 2
    grantTx = sixgr.mac.ra.buildRARULGrant(raCfg);
    rapid = double(raCfg.PreambleIndex);
    if faultMode == "wrong_rapid_in_rar"
        rapid = mod(rapid + 1, 64);
    end
    rarTx = sixgr.mac.ra.encodeMACRAR("RAPID", rapid, ...
        "TimingAdvanceCommand", double(ta.TimingAdvanceCommand), ...
        "TemporaryCRNTI", double(raCfg.TempCRNTI), ...
        "ULGrant", grantTx);
    localProgress(opt, "msg2_tx_start", "");
    [msg2Tx, msg2Sched] = sixgr.phy.ra.generateMsg2RARWaveform(cfg, raCfg, rarTx);
    localProgress(opt, "msg2_tx_done", sprintf("samples=%d", size(msg2Tx.Waveform, 1)));
    [msg2Tx.Waveform, msg2Power] = localApplyWaveformTxPower(msg2Tx.Waveform, ...
        powerState.Msg2TxPower_dBm, powerState.ReferenceTxPower_dBm);
    msg2Tx.PowerControl = powerState;
    msg2Tx.PowerControl.Msg2TxAmplitudeScale = double(msg2Power.AmplitudeScale);
    result.Msg2TxAmplitudeScale = double(msg2Power.AmplitudeScale);
    withinWindow = logical(raTiming.RARInsideWindow);
    if faultMode == "response_window_expiry"
        withinWindow = false;
    end
    attemptedRNTI = double(raCfg.RARNTI);
    if faultMode == "wrong_ra_rnti"
        attemptedRNTI = double(raCfg.RARNTI) + 1;
    end
    end
    if prepareOnly || ~localStageReceiveReady(cfg, raCfg, "Msg2", msg2Tx.Waveform, msg2Tx, opt, runtime.StageWaveforms)
        prepared = struct("Msg2Schedule", msg2Sched, "WithinWindow", withinWindow, ...
            "AttemptedRNTI", attemptedRNTI, "RARTx", rarTx);
        [result, continuation] = captureContinuation(2, prepared, msg2Tx.Waveform, msg2Tx, "DL");
        return;
    end
    localProgress(opt, "msg2_channel_start", "");
    [msg2RxWave, runtime, stageInfo] = localResolveStageRxWaveform("Msg2", "DL", msg2Tx.Waveform, cfg, raCfg, msg2Tx, runtime);
    localProgress(opt, "msg2_channel_done", "");
    result = localAppendRuntimeStage(result, stageInfo, runtime);
    localProgress(opt, "msg2_pdcch_start", "");
    [pdcchRx, pdcchInfo] = sixgr.phy.ra.blindDecodeRARPDCCH(msg2RxWave, cfg, raCfg, msg2Sched, ...
        "RNTIAttempted", attemptedRNTI);
    localProgress(opt, "msg2_pdcch_done", sprintf("ok=%d", logical(pdcchRx.Ok)));
    msg2WaveForPDSCH = msg2RxWave;
    if faultMode == "rar_pdsch_corrupted"
        msg2WaveForPDSCH = localCorruptWaveform(msg2WaveForPDSCH, 0.75);
    end
    rarRx = struct();
    pdschRx2 = struct("Ok", false, "CRCError", true);
    if logical(pdcchRx.Ok) && withinWindow
        cfgMsg2Rx = localApplyRuntimeReceiverSyncContext(cfg, runtime, "DL");
        localProgress(opt, "msg2_pdsch_start", "");
        [pdschRx2, rarRx] = sixgr.phy.ra.recoverMsg2RAR(msg2WaveForPDSCH, cfgMsg2Rx, raCfg, msg2Sched, msg2Tx);
        localProgress(opt, "msg2_pdsch_done", sprintf("ok=%d", logical(sixgr.util.structGet(pdschRx2, "Ok", false))));
    end
    rapidMatches = isstruct(rarRx) && isfield(rarRx, "RAPID") && double(rarRx.RAPID) == double(raCfg.PreambleIndex);
    if isstruct(rarRx) && isfield(rarRx, "ULGrant")
        grantRx = rarRx.ULGrant;
        % Preserve the MCS/modulation/rate and allocation decoded from RAR;
        % never overwrite them with the transmitter's scheduled values.
        grantRx.TemporaryCRNTI = double(rarRx.TemporaryCRNTI);
    else
        grantRx = struct();
    end
    grantValidation = sixgr.mac.ra.validateRARULGrant(grantRx, raCfg);
    result = localApplyMsg2(result, raCfg, withinWindow, pdcchRx, pdcchInfo, pdschRx2, msg2Tx, rarTx, rarRx, rapidMatches, grantValidation);
    if ~withinWindow || ~logical(pdcchRx.Ok) || ~logical(sixgr.util.structGet(pdschRx2, "Ok", false)) || ~rapidMatches || ~logical(grantValidation.Valid)
        result = localFail(result, localFailureForMsg2(withinWindow, pdcchRx, pdschRx2, rapidMatches, grantValidation), "MSG2_RAR_RX");
        result = localFinalize(result, raCfg, events, timerRows, oracleRows, msg1Tx, det, msg2Tx, pdcchInfo, pdschRx2, rarRx, struct(), struct(), struct(), opt);
        return;
    end
    events = [events; localEvent(raCfg, "MSG2_RAR_TX", "MSG2_RAR_RX", "rar_pdcch_pdsch_decode", "ra-ResponseWindow", ...
        double(raCfg.RAResponseWindowSlots), double(raCfg.RARNTI), double(raCfg.PreambleIndex), "", double(raCfg.Msg2Slot))]; %#ok<AGROW>
    timerRows = [timerRows; localTimer(raCfg, "ra-ResponseWindow", "stop", double(raCfg.PRACHOccasionEndSlot + 1), double(raCfg.Msg2Slot), ...
        double(raCfg.PRACHOccasionEndSlot + raCfg.RAResponseWindowSlots), false, double(raCfg.RAResponseWindowSlots), "OK")]; %#ok<AGROW>

    if stopStage == 2
        [result, continuation] = captureContinuation(3);
        return;
    end
    end

    if nextStage <= 3
    if reusePreparedStage ~= 3
    localProgress(opt, "msg3_tx_start", "");
    powerState = sixgr.mac.ra.applyRARGrantPowerCommand(powerState, grantRx);
    result = localApplyPowerStateToResult(result, powerState);
    ueIdentity = "UE-" + string(round(double(raCfg.UEId)));
    msg3TxPayload = sixgr.mac.ra.buildMsg3Payload( ...
        "UEId", double(raCfg.UEId), ...
        "UEIdentity", ueIdentity, ...
        "RRCSetupRequest", true);
    [msg3Tx, pusch] = sixgr.phy.ra.generateMsg3PUSCHWaveform(cfg, raCfg, grantRx, msg3TxPayload);
    localProgress(opt, "msg3_tx_done", sprintf("samples=%d", size(msg3Tx.Waveform, 1)));
    [msg3Tx.Waveform, msg3Power] = localApplyWaveformTxPower(msg3Tx.Waveform, ...
        powerState.Msg3TxPower_dBm, powerState.ReferenceTxPower_dBm);
    msg3Tx.PowerControl = powerState;
    msg3Tx.PowerControl.Msg3TxAmplitudeScale = double(msg3Power.AmplitudeScale);
    result.Msg3TxAmplitudeScale = double(msg3Power.AmplitudeScale);
    msg3TA = sixgr.phy.ra.applyDecodedRARTimingAdvance(msg3Tx.Waveform, ...
        rarRx,raCfg.CarrierSCSkHz,localStageSampleRate(localStageTxInfo(msg3Tx),msg3Tx));
    result.TimingAdvanceSamples = msg3TA.RARTiming.Samples;
    result.TimingAdvanceSampleRate_Hz = msg3TA.RARTiming.SampleRateHz;
    result.TimingAdvanceNTA_Tc = msg3TA.RARTiming.NTA_Tc;
    result.TimingAdvanceSource = msg3TA.TimingAdvanceSource;
    end
    if prepareOnly || ~localStageReceiveReady(cfg, raCfg, "Msg3", msg3TA.Waveform, msg3Tx, opt, runtime.StageWaveforms)
        prepared = struct("Msg3Payload", msg3TxPayload, "PUSCH", pusch, "TimingAdvanceWaveform", msg3TA);
        [result, continuation] = captureContinuation(3, prepared, msg3TA.Waveform, msg3Tx, "UL");
        return;
    end
    localProgress(opt, "msg3_channel_start", "");
    [msg3Wave, runtime, stageInfo] = localResolveStageRxWaveform("Msg3", "UL", msg3TA.Waveform, cfg, raCfg, msg3Tx, runtime);
    localProgress(opt, "msg3_channel_done", "");
    result = localAppendRuntimeStage(result, stageInfo, runtime);
    if faultMode == "msg3_pusch_corrupted"
        % Apply a deterministic waveform-domain impairment relative to the
        % actual post-power-control Msg3 RMS power.  An absolute noise
        % amplitude is invalid here because open-loop power control may scale
        % otherwise identical Msg3 waveforms by many tens of decibels.
        msg3Wave = localCorruptWaveformAtSNR(msg3Wave, -20);
    end
    cfgMsg3Rx = localApplyRuntimeReceiverSyncContext(cfg, runtime, "UL");
    localProgress(opt, "msg3_pusch_start", "");
    [msg3Rx, msg3Decoded] = sixgr.phy.ra.recoverMsg3PUSCH( ...
        msg3Wave, cfgMsg3Rx, raCfg, grantRx, msg3Tx);
    localProgress(opt, "msg3_pusch_done", sprintf("ok=%d", logical(sixgr.util.structGet(msg3Rx, "Ok", false))));
    result = localApplyMsg3(result, raCfg, grantRx, msg3TxPayload, msg3Rx, msg3Decoded, pusch);
    if ~logical(sixgr.util.structGet(msg3Rx, "Ok", false)) || ...
            ~isfield(msg3Decoded, "ContentionIdentity") || ...
            ~logical(sixgr.util.structGet( ...
            msg3Decoded, "RRCSetupRequestPresent", false))
        result = localFail(result, "msg3_pusch_crc_fail", "MSG3_PUSCH_RX");
        result = localFinalize(result, raCfg, events, timerRows, oracleRows, msg1Tx, det, msg2Tx, pdcchInfo, pdschRx2, rarRx, msg3Tx, msg3Rx, struct(), opt);
        return;
    end
