function det = localAttachMsg1ReferenceEvidence(det, stageInfo)
% Attach scoring truth only after the detector has produced its estimate.
% The locally generated and runtime-channel waveforms share the resolved
% PRACH-occasion origin.  Runtime fading objects are filter-delay trimmed by
% ChannelFactory, so zero is the transmitted occasion reference, not a
% receiver oracle.  Externally supplied waveforms have no known reference.
knownReference = logical(sixgr.util.structGet(stageInfo, "SelfLoopWaveformUsed", false)) || ...
    logical(sixgr.util.structGet(stageInfo, "RuntimeChannelStateUsed", false));
if knownReference
    trueOffset = 0;
    referenceSource = "resolved_prach_occasion_waveform_origin";
else
    trueOffset = NaN;
    referenceSource = "unavailable_for_external_runtime_waveform";
end
estimate = double(sixgr.util.structGet(det, "PropagationTimingOffsetSamples", NaN));
det.TrueTimingOffsetSamples = double(trueOffset);
if isfinite(estimate) && isfinite(trueOffset)
    det.TimingErrorSamples = double(estimate - trueOffset);
else
    det.TimingErrorSamples = NaN;
end
det.TimingReferenceSource = referenceSource;
end

