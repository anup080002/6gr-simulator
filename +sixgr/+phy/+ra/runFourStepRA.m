function [waveform,nVar,info] = localAddRuntimeStageNoise( ...
        desiredWaveform,txInfo,cfg,snr_dB,replay)
mode = lower(strtrim(string(sixgr.util.structGet(cfg, ...
    "run.noiseOperatingMode","receiver_noise_figure_thermal_noise"))));
referencePower = localFiniteWaveformPower(desiredWaveform,txInfo);
switch mode
    case "standalone_awgn_snr_argument"
        if ~(isfinite(double(snr_dB)) && isfinite(referencePower) && referencePower > 0)
            error("sixgr:phy:ra:InvalidRuntimeNoiseReference", ...
                "Standalone RA runtime noise requires finite SNR and desired-waveform power.");
        end
        nVar = referencePower/10.^(double(snr_dB)/10);
        noise = sqrt(nVar/2).*(randn(size(desiredWaveform), ...
            "like",real(desiredWaveform))+1i*randn(size(desiredWaveform), ...
            "like",real(desiredWaveform)));
        waveform = desiredWaveform+cast(noise,"like",desiredWaveform);
        info = struct( ...
            "AppliedAWGNSNR_dB",double(snr_dB), ...
            "InjectedNoiseVariance",double(nVar), ...
            "NoiseVarianceSource","standalone_awgn_receiver_sample_reference", ...
            "NoiseOperatingMode",char(mode), ...
            "SNRReferencePlane","receiver_sample_waveform_pre_composite_front_end", ...
            "SampleNoiseVariance",double(nVar), ...
            "SampleNoiseVarianceDomain","receiver_sample_waveform_pre_composite_front_end");
    case "receiver_noise_figure_thermal_noise"
        nVar = sixgr.link.resolveReceiverThermalNoiseVariance(replay);
        noise = sqrt(nVar/2).*(randn(size(desiredWaveform), ...
            "like",real(desiredWaveform))+1i*randn(size(desiredWaveform), ...
            "like",real(desiredWaveform)));
        waveform = desiredWaveform+cast(noise,"like",desiredWaveform);
        info = struct( ...
            "AppliedAWGNSNR_dB",NaN, ...
            "InjectedNoiseVariance",double(nVar), ...
            "NoiseVarianceSource","receiver_thermal_psd_times_sample_rate_absolute_sqrt_mW", ...
            "NoiseOperatingMode",char(mode), ...
            "SNRReferencePlane","receiver_sample_waveform_pre_composite_front_end", ...
            "SampleNoiseVariance",double(nVar), ...
            "SampleNoiseVarianceDomain","receiver_sample_waveform_pre_composite_front_end");
    otherwise
        error("sixgr:phy:ra:UnsupportedNoiseOperatingMode", ...
            "Unsupported RA runtime noise mode '%s'.",char(mode));
end
info.DesiredSignalPowerBeforeNoise=referencePower;
info.AppliedNoiseSNR_dB=10*log10(referencePower/nVar);
info.AppliedNoiseSNRSource= ...
    "actual_pre_noise_active_OFDM_reference_power_per_branch_over_injected_sample_variance_not_UE_report";
end

