        double(raCfg.TempCRNTI), double(raCfg.PreambleIndex), "", double(raCfg.Msg3Slot))]; %#ok<AGROW>

    if stopStage == 3
        [result, continuation] = captureContinuation(4);
        return;
    end
    end

    if nextStage <= 4
    if reusePreparedStage ~= 4
    msg4Identity = msg3Decoded.ContentionIdentity;
    if faultMode == "msg4_identity_mismatch"
        msg4Identity = "FFFFFFFFFFFF";
    end
    if faultMode == "contention_resolution_timer_expiry" || ...
            ~logical(raTiming.ContentionResolved)
        result = localFail(result, "contention_resolution_timer_expired", "MSG4_CONTENTION_RESOLUTION_RX");
        timerRows = [timerRows; localTimer(raCfg, "ra-ContentionResolutionTimer", "expire", double(raCfg.Msg3Slot), NaN, ...
            double(raTiming.ContentionExpirySlotExclusive), true, double(raCfg.RAContentionResolutionTimerSlots), "expired")]; %#ok<AGROW>
        result = localFinalize(result, raCfg, events, timerRows, oracleRows, msg1Tx, det, msg2Tx, pdcchInfo, pdschRx2, rarRx, msg3Tx, msg3Rx, struct(), opt);
        return;
    end
    localProgress(opt, "msg4_tx_start", "");
    setupTransactionID = double(raCfg.RRCTransactionID);
    if ~logical(raCfg.RequireRRCSetupComplete)
        setupTransactionID = 0;
    end
    msg4TxPayload = sixgr.mac.ra.buildMsg4ContentionResolution( ...
        msg4Identity, ...
        "FinalCRNTI", double(raCfg.FinalCRNTI), ...
        "RRCSetup", logical(raCfg.RequireRRCSetupComplete), ...
        "TransactionID", setupTransactionID, ...
        "SRB1LCID", max(1, double(raCfg.SRB1LCID)));
    [msg4Tx, msg4Sched] = sixgr.phy.ra.generateMsg4Waveform(cfg, raCfg, msg4TxPayload);
    localProgress(opt, "msg4_tx_done", sprintf("samples=%d", size(msg4Tx.Waveform, 1)));
    [msg4Tx.Waveform, msg4Power] = localApplyWaveformTxPower(msg4Tx.Waveform, ...
        powerState.Msg4TxPower_dBm, powerState.ReferenceTxPower_dBm);
    msg4Tx.PowerControl = powerState;
    msg4Tx.PowerControl.Msg4TxAmplitudeScale = double(msg4Power.AmplitudeScale);
    result.Msg4TxAmplitudeScale = double(msg4Power.AmplitudeScale);
    end
    if prepareOnly || ~localStageReceiveReady(cfg, raCfg, "Msg4", msg4Tx.Waveform, msg4Tx, opt, runtime.StageWaveforms)
        prepared = struct("Msg4Schedule", msg4Sched, "Msg4Payload", msg4TxPayload);
        [result, continuation] = captureContinuation(4, prepared, msg4Tx.Waveform, msg4Tx, "DL");
        return;
    end
    localProgress(opt, "msg4_channel_start", "");
    [msg4RxWave, runtime, stageInfo] = localResolveStageRxWaveform("Msg4", "DL", msg4Tx.Waveform, cfg, raCfg, msg4Tx, runtime);
    localProgress(opt, "msg4_channel_done", "");
    result = localAppendRuntimeStage(result, stageInfo, runtime);
    cfgMsg4Rx = localApplyRuntimeReceiverSyncContext(cfg, runtime, "DL");
    localProgress(opt, "msg4_rx_start", "");
    [msg4PdcchRx, msg4PdschRx, msg4Decoded] = sixgr.phy.ra.recoverMsg4Waveform(msg4RxWave, cfgMsg4Rx, raCfg, msg4Sched, msg4Tx);
    localProgress(opt, "msg4_rx_done", sprintf("pdcch=%d pdsch=%d", ...
        logical(sixgr.util.structGet(msg4PdcchRx, "Ok", false)), logical(sixgr.util.structGet(msg4PdschRx, "Ok", false))));
    result = localApplyMsg4(result, raCfg, msg3Decoded, msg4PdcchRx, msg4PdschRx, msg4Tx, msg4Decoded, msg4TxPayload);
    rrcSetupDecoded = ~logical(raCfg.RequireRRCSetupComplete) || ...
        (logical(sixgr.util.structGet( ...
        msg4Decoded, "RRCSetupPresent", false)) && ...
        double(sixgr.util.structGet( ...
        msg4Decoded, "RRCSetup.TransactionID", NaN)) == ...
        double(raCfg.RRCTransactionID) && ...
        double(sixgr.util.structGet( ...
        msg4Decoded, "RRCSetup.SRB1LCID", NaN)) == ...
        double(raCfg.SRB1LCID));
    if faultMode == "rrc_setup_transaction_mismatch"
        rrcSetupDecoded = false;
    end
    if ~logical(result.ContentionIdentityMatches)
        result = localFail(result, "contention_resolution_identity_mismatch", "MSG4_CONTENTION_RESOLUTION_RX");
    elseif ~rrcSetupDecoded
        result = localFail(result, "rrc_setup_transaction_or_srb1_mismatch", ...
            "MSG4_RRC_SETUP_RX");
    else
        result.RACompleted = true;
        result.FinalCRNTI = double(raCfg.FinalCRNTI);
        result.FailureReason = "";
        events = [events; localEvent(raCfg, "MSG4_CONTENTION_RESOLUTION_RX", "RA_SUCCESS", ...
            "contention_resolution_identity_match", "ra-ContentionResolutionTimer", ...
            double(raCfg.RAContentionResolutionTimerSlots), double(raCfg.TempCRNTI), ...
            double(raCfg.PreambleIndex), "", double(raCfg.Msg4Slot))]; %#ok<AGROW>
        timerRows = [timerRows; localTimer(raCfg, "ra-ContentionResolutionTimer", "stop", double(raCfg.Msg3Slot), double(raCfg.Msg4Slot), ...
            double(raTiming.ContentionExpirySlotExclusive), false, double(raCfg.RAContentionResolutionTimerSlots), "OK")]; %#ok<AGROW>
    end
    result.RRCSetupRequestDecoded = logical(sixgr.util.structGet( ...
        msg3Decoded, "RRCSetupRequestPresent", false));
    result.RRCSetupRequestSHA256 = string(sixgr.util.structGet( ...
        msg3Decoded, "RRCSetupRequestSHA256", ""));
    result.RRCSetupDecoded = logical(rrcSetupDecoded);
    result.RRCSetupSHA256 = string(sixgr.util.structGet( ...
        msg4Decoded, "RRCSetupSHA256", ""));
    if stopStage == 4 && logical(result.RACompleted) && logical(raCfg.RequireRRCSetupComplete)
        [result, continuation] = captureContinuation(5);
        return;
    end
    end

    if logical(result.RACompleted) && ...
            logical(raCfg.RequireRRCSetupComplete)
        if reusePreparedStage ~= 5
        localProgress(opt, "rrc_setup_complete_tx_start", "");
        setupCompleteTxPayload = sixgr.mac.ra.buildRRCSetupComplete( ...
            "TransactionID", double(raCfg.RRCTransactionID), ...
            "SRB1LCID", double(raCfg.SRB1LCID), ...
            "UEIdentity", ueIdentity);
        [setupCompleteTx, setupCompletePUSCH] = ...
            sixgr.phy.ra.generateRRCSetupCompleteWaveform( ...
            cfg, raCfg, grantRx, setupCompleteTxPayload);
        [setupCompleteTx.Waveform, setupPower] = ...
            localApplyWaveformTxPower( ...
            setupCompleteTx.Waveform, ...
            powerState.Msg3TxPower_dBm, ...
            powerState.ReferenceTxPower_dBm);
        % RRCSetupComplete is an SRB1 UL transmission and inherits the
        % same configured/open-loop PUSCH power authority as Msg3.  Keep
        % that typed state attached to the waveform so the runtime
        % PowerContext cannot silently fall back to a generic UE limit.
        setupCompleteTx.PowerControl = powerState;
        setupCompleteTx.PowerControl.Msg3TxAmplitudeScale = ...
            double(setupPower.AmplitudeScale);
        result.SetupCompleteTxAmplitudeScale = ...
            double(setupPower.AmplitudeScale);
        setupCompleteTA = sixgr.phy.ra.applyDecodedRARTimingAdvance( ...
            setupCompleteTx.Waveform,rarRx,raCfg.CarrierSCSkHz, ...
            localStageSampleRate(localStageTxInfo(setupCompleteTx),setupCompleteTx));
        end
        if prepareOnly || ~localStageReceiveReady(cfg, raCfg, "RRCSetupComplete", ...
                setupCompleteTA.Waveform, setupCompleteTx, opt, runtime.StageWaveforms)
            prepared = struct("Tx", setupCompleteTx, "Payload", setupCompleteTxPayload, ...
                "PUSCH", setupCompletePUSCH, "TimingAdvanceWaveform", setupCompleteTA);
            [result, continuation] = captureContinuation(5, prepared, ...
                setupCompleteTA.Waveform, setupCompleteTx, "UL");
            return;
        end
        [setupCompleteWave, runtime, stageInfo] = ...
            localResolveStageRxWaveform( ...
            "RRCSetupComplete", "UL", ...
            setupCompleteTA.Waveform, cfg, raCfg, ...
            setupCompleteTx, runtime);
        result = localAppendRuntimeStage(result, stageInfo, runtime);
        if any(faultMode == [ ...
                "rrc_setup_complete_corrupted", ...
                "rrc_setup_complete_crc_failure"])
            setupCompleteWave = localCorruptWaveform( ...
                setupCompleteWave, 1.5);
        end
        [setupCompleteRx, setupCompleteDecoded] = ...
            sixgr.phy.ra.recoverRRCSetupComplete( ...
            setupCompleteWave, ...
            localApplyRuntimeReceiverSyncContext(cfg, runtime, "UL"), ...
            raCfg, setupCompleteTx);
        result.SetupCompleteTx = setupCompleteTx;
        result.SetupCompleteRx = setupCompleteRx;
        result.SetupCompletePUSCH = setupCompletePUSCH;
        result.SetupCompleteTransportBlockSize = double( ...
            sixgr.util.structGet(setupCompleteTx, "TransportBlockSize", NaN));
        result.SetupCompleteReceiverOk = logical(sixgr.util.structGet( ...
            setupCompleteRx, "Ok", false));
        result.SetupCompletePostEqSINR_dB = double(sixgr.util.structGet( ...
            setupCompleteRx, "PostEqSINR_dB", NaN));
        result.SetupCompleteReceiverHestSINR_dB = double(sixgr.util.structGet( ...
            setupCompleteRx, "ReceiverHestSINR_dB", NaN));
        result.SetupCompleteChannelEstimateAvailable = logical(sixgr.util.structGet( ...
            setupCompleteRx, "ChannelEstimateAvailable", false));
        result.SetupCompleteChannelEstimateMethod = string(sixgr.util.structGet( ...
            setupCompleteRx, "ChannelEstimateMethod", ""));
        result.SetupCompleteEqualizationAvailable = logical(sixgr.util.structGet( ...
            setupCompleteRx, "EqualizationAvailable", false));
        result.SetupCompleteLLRFinite = logical(sixgr.util.structGet( ...
            setupCompleteRx, "LLRFinite", false));
        result.SetupCompleteDemapperLLRCount = double(sixgr.util.structGet( ...
            setupCompleteRx, "DemapperLLRCount", NaN));
        result.SetupCompleteDecoderIterations = double(sixgr.util.structGet( ...
            setupCompleteRx, "DecoderIterations", NaN));
        result.RRCSetupCompletePayloadSHA256 = string( ...
            setupCompleteTxPayload.PayloadHash);
        decodedTransaction = double(sixgr.util.structGet( ...
            setupCompleteDecoded, "TransactionID", NaN));
        decodedLCID = double(sixgr.util.structGet( ...
            setupCompleteDecoded, "SRB1LCID", NaN));
        decodedIdentity = string(sixgr.util.structGet( ...
            setupCompleteDecoded, "UEIdentity", ""));
        if faultMode == "rrc_setup_complete_transaction_mismatch"
            decodedTransaction = mod(decodedTransaction + 1, 4);
        elseif faultMode == "rrc_setup_complete_identity_mismatch"
            decodedIdentity = "UE-WRONG";
        end
        result.RRCSetupCompleteDecodedTransactionID = decodedTransaction;
        result.RRCSetupCompleteDecodedSRB1LCID = decodedLCID;
        result.RRCSetupCompleteDecodedUEIdentity = decodedIdentity;
        setupCompleteCRC = logical(sixgr.util.structGet( ...
            setupCompleteRx, "Ok", false));
        setupCompleteInsideTimer = ...
            double(raCfg.SetupCompleteSlot) > double(raCfg.Msg4Slot);
        if faultMode == "rrc_setup_complete_late"
            setupCompleteInsideTimer = false;
        end
        result.RRCSetupCompleteCRC = setupCompleteCRC;
        result.RRCSetupCompleteDecoded = ...
            setupCompleteCRC && setupCompleteInsideTimer && ...
            decodedTransaction == double(raCfg.RRCTransactionID) && ...
            decodedLCID == double(raCfg.SRB1LCID) && ...
            decodedIdentity == ueIdentity;
