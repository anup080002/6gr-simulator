function [ant, meta] = localLogicalPortViewForStage( ...
        ant, meta, portCount, projection, mappingSource, beamId)
portCount = max(1, round(double(portCount)));
if ~(isstruct(ant) && ~isempty(fieldnames(ant)))
    ant = struct();
end
if ~(isstruct(meta) && ~isempty(fieldnames(meta)))
    meta = struct();
end
% Use the same logical-port authority as every other runtime waveform.  The
% former RA-local copy omitted PortToElementExpansionEnabled, so a one-port
% Msg1 waveform reached a two-element required-pattern CDL endpoint without
% the power-preserving element projection that had already been resolved.
[ant, meta] = sixgr.rf.AntennaArrayFactory.logicalPortView( ...
    ant, meta, portCount, "four_step_ra_stage_logical_waveform_ports");
numElements = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "NumElements", []), ...
    sixgr.util.structGet(ant, "NumElements", []), ...
    sixgr.util.structGet(ant, "Nant", []), ...
    portCount);
proj = projection;
if isempty(proj)
    proj = localPortProjectionMatrix(numElements, portCount);
end
if ~isequal(size(proj), [round(numElements) portCount])
    error("sixgr:phy:ra:StagePortProjectionDimensionMismatch", ...
        ["The configured %s projection for stage %s has size %dx%d; " ...
         "the runtime antenna requires %dx%d."], ...
        char(mappingSource), char(beamId), size(proj, 1), size(proj, 2), ...
        round(numElements), portCount);
end
gramResidual = norm(proj' * proj - eye(portCount, "like", proj), "fro");
if gramResidual > 1e-9 * max(1, portCount)
    error("sixgr:phy:ra:StagePortProjectionNotPowerPreserving", ...
        "The configured %s projection is not power preserving (residual %.3g).", ...
        char(mappingSource), gramResidual);
end
ant.PortToElementMatrix = proj;
ant.ElementToPortMatrix = proj';
ant.HybridElementToPortMatrix = proj;
ant.PortToElementMappingSource = char(mappingSource);
ant.SelectedBeamId = char(beamId);
meta.PortToElementMatrix = proj;
meta.PortToElementMappingSource = char(mappingSource);
meta.SelectedBeamId = char(beamId);
end

function [projection, mappingSource, beamId] = localStagePortProjection( ...
        cfg, ant, meta, direction, endpoint, portCount, stageName)
projection = [];
mappingSource = "runtime_antenna_mapping";
beamId = "";
numElements = round(localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "NumElements", []), ...
    sixgr.util.structGet(ant, "NumElements", []), ...
    sixgr.util.structGet(ant, "Nant", []), portCount));

isCommonDLTx = upper(strtrim(string(direction))) == "DL" && ...
    lower(strtrim(string(endpoint))) == "tx" && ...
    ismember(string(stageName), ["Msg2","Msg4"]);
if isCommonDLTx
    mappingSource = lower(strtrim(string(sixgr.util.structGet(cfg, ...
        "random_access.common_downlink_beam_source", "runtime_antenna_mapping"))));
end

switch mappingSource
    case "selected_ssb_beam"
        if portCount ~= 1
            error("sixgr:phy:ra:CommonDownlinkBeamRequiresSinglePort", ...
                "RA common downlink stage %s must use one logical port for selected_ssb_beam.", ...
                char(string(stageName)));
        end
        matrices = sixgr.util.structGet(cfg, "phy.ssb.precoderMatrices", []);
        selectedIndex = double(sixgr.util.structGet(cfg, ...
            "phy.ssb.runtimeSSBIndex", NaN));
        ids = string(sixgr.util.structGet(cfg, "phy.ssb.precoderIDs", strings(0, 1)));
        if ~(isnumeric(matrices) && ismatrix(matrices) && ...
                size(matrices, 2) == numElements && ...
                isfinite(selectedIndex) && selectedIndex == fix(selectedIndex) && ...
                selectedIndex >= 0 && selectedIndex < size(matrices, 1))
            error("sixgr:phy:ra:SelectedSSBBeamUnavailable", ...
                strcat( ...
                    "random_access.common_downlink_beam_source=selected_ssb_beam ", ...
                    "requires a valid zero-based phy.ssb.runtimeSSBIndex and an ", ...
                    "SSB precoder matrix matching the physical gNB array."));
        end
        projection = matrices(selectedIndex + 1, :).';
        if numel(ids) >= selectedIndex + 1
            beamId = ids(selectedIndex + 1);
        else
            beamId = "ssb_index_" + string(selectedIndex);
        end
    case "runtime_antenna_mapping"
        candidate = sixgr.util.structGet(ant, "PortToElementMatrix", []);
        if isnumeric(candidate) && isequal(size(candidate), [numElements portCount])
            projection = candidate;
        else
            projection = localPortProjectionMatrix(numElements, portCount);
            mappingSource = "runtime_antenna_partition_from_yaml_port_count";
        end
    otherwise
        error("sixgr:phy:ra:UnsupportedCommonDownlinkBeamSource", ...
            "Unsupported random_access.common_downlink_beam_source '%s'.", ...
            char(mappingSource));
end
end

function proj = localPortProjectionMatrix(numElements, numPorts)
numElements = max(1, round(double(numElements)));
numPorts = max(1, round(double(numPorts)));
proj = zeros(numElements, numPorts);
edges = round(linspace(0, numElements, numPorts + 1));
for pIdx = 1:numPorts
    idx = (edges(pIdx) + 1):max(edges(pIdx + 1), edges(pIdx) + 1);
    idx = idx(idx >= 1 & idx <= numElements);
    if isempty(idx)
        idx = min(numElements, pIdx);
    end
    proj(idx, pIdx) = 1 / sqrt(max(1, numel(idx)));
end
end

