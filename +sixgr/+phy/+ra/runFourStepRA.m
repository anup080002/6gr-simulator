            if ~setupCompleteCRC
                rrcEventSequence = ...
                    "CELL_SELECTED|MSG3_RRC_SETUP_REQUEST_OK|" + ...
                    "MSG4_RRC_SETUP_OK|UL_DCCH_CRC_FAIL";
