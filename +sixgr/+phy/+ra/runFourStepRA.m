function [rxWave, runtime, row] = localResolveStageRxWaveform(stageName, direction, txWave, cfg, raCfg, txStruct, runtime)
stageName = string(stageName);
direction = upper(strtrim(string(direction)));
row = localEmptyRuntimeStageRow();
row.RunId = string(raCfg.RunId);
row.CellId = double(raCfg.CellId);
row.UEId = double(raCfg.UEId);
row.AttemptId = double(raCfg.AttemptId);
row.StageName = stageName;
row.Direction = direction;
row.TxSampleCount = size(txWave, 1);
row.TxPortCount = size(txWave, 2);
row.RuntimeIntegrationMode = string(runtime.Mode);
row.RuntimeTransportMode = string(runtime.TransportMode);
row.StageSlot = localStageSlot(raCfg, stageName);
rxWave = txWave;

[provided, providedField] = localRuntimeProvidedWaveform(runtime.StageWaveforms, stageName);
if ~isempty(provided)
    if isa(provided, 'sixgr.phy.waveform.WaveformObservationBuffer')
        localAssertRAObservationLayout(provided,cfg,raCfg,stageName,txWave,txStruct);
        % readComplete rejects a planned but incompletely received window.
        % No channel, TX, RF or noise operation belongs on this path.
        rxWave = provided.readComplete();
        row.ObservationStartSample = provided.StartSample;
        row.ObservationEndSampleExclusive = provided.EndSampleExclusive;
        row.ObservationSampleRateHz = provided.SampleRateHz;
        row.ObservationCompletionTime_s = provided.EndSampleExclusive / provided.SampleRateHz;
        row.ObservationCoverageSource = "complete_contiguous_received_sample_buffer";
        row.WaveformSource = "provided_contiguous_received_sample_buffer";
    else
        rxWave = provided;
        row.WaveformSource = "provided_runtime_stage_waveform";
    end
    localAssertRuntimeWaveformCompatible(rxWave, txWave, stageName, providedField, ...
        isa(provided,'sixgr.phy.waveform.WaveformObservationBuffer'));
    row.RxSampleCount = size(rxWave, 1);
    row.RxPortCount = size(rxWave, 2);
    row.ProvidedWaveformField = providedField;
    row.RuntimeStageWaveformUsed = true;
    row.SelfLoopWaveformUsed = false;
    runtime.StageRows(end + 1, 1) = row;
    return;
end

if logical(runtime.RequireStageWaveforms)
    if logical(runtime.AllowStageWaveformComposition) && logical(runtime.UseRuntimeChannel)
        [rxWave, runtime, row] = localApplyRuntimeChannelForStage(row, direction, txWave, cfg, txStruct, runtime);
        row.WaveformSource = "coupled_runtime_stage_waveform_composer";
        row.RuntimeStageWaveformUsed = true;
        row.ProvidedWaveformField = "runtime_channel_state";
        runtime.StageRows(end + 1, 1) = row;
        return;
    end
    error("sixgr:phy:ra:MissingRuntimeStageWaveform", ...
        "Four-step RA runtime mode requires a propagated receive waveform for %s, but none was provided.", stageName);
end

if logical(runtime.UseRuntimeChannel)
    [rxWave, runtime, row] = localApplyRuntimeChannelForStage(row, direction, txWave, cfg, txStruct, runtime);
    row.RuntimeStageWaveformUsed = true;
    runtime.StageRows(end + 1, 1) = row;
    return;
end

row.RxSampleCount = size(rxWave, 1);
row.RxPortCount = size(rxWave, 2);
row.WaveformSource = "standalone_self_loop_waveform";
row.SelfLoopWaveformUsed = true;
runtime.StageRows(end + 1, 1) = row;
end

function [rxWave, runtime, row] = localApplyRuntimeChannelForStage(row, direction, txWave, cfg, txStruct, runtime)
cfgStage = localRuntimeStageConfig(cfg, direction, runtime);
cfgStage = sixgr.util.structSet(cfgStage, ...
    "lls6g.userContext.RuntimeSignalFamily",char(string(row.StageName)));
cfgStage = sixgr.util.structSet(cfgStage, ...
    "phy.runtimeSignalFamily",char(string(row.StageName)));
cfgStage = sixgr.util.structSet(cfgStage, ...
    "channel.linkDirection",char(direction));
txInfo = localStageTxInfo(txStruct);
[targetTxPower_dBm,targetTxPowerSource] = localStageTransmitPower( ...
    txStruct,string(row.StageName),cfgStage,direction);
powerContext = sixgr.rf.PowerContext(cfgStage,direction, ...
    "NumPorts",size(txWave,2));
if isfinite(targetTxPower_dBm)
    powerContext.TotalTxPower_dBm = double(targetTxPower_dBm);
    powerContext.TotalTxPower_mW = 10.^(double(targetTxPower_dBm)/10);
    powerContext.TotalTxPower_W = powerContext.TotalTxPower_mW*1e-3;
    powerContext.TotalTxPowerSource = char(targetTxPowerSource);
end
powerContext.SignalSpecificPowerControl = true;
powerContext.SignalFamily = char(string(row.StageName));
[txWave,powerContext] = sixgr.rf.applyPowerContext( ...
    txWave,cfgStage,direction,txInfo,"PowerContext",powerContext);
cfgStage = sixgr.util.structSet(cfgStage, ...
    "lls6g.runtimePowerContext",powerContext);
sampleRateHz = localStageSampleRate(txInfo,txStruct);
txRF = sixgr.rf.applyRFImpairmentChain(txWave,cfgStage, ...
    "SampleRateHz",sampleRateHz, ...
    "Direction",char(direction), ...
    "MeasurementPoint","tx_output", ...
    "Endpoint","tx", ...
    "StrictMutationRequired",false, ...
    "UseLegacyGlobalConfig",false, ...
    "ApplyPA",false, ...
    "ApplyADC",false);
txWave = cast(txRF.Waveform,"like",txWave);
cfgStage = sixgr.util.structSet(cfgStage, ...
    "lls6g.txRFImpairmentReplay",txRF.Replay);
row.AppliedTxPower_dBm = double(powerContext.TotalTxPower_dBm);
row.MeasuredTxPowerBeforeRF_dBm = double(powerContext.OutputTotalPower_dBm);
row.TxPowerClosureError_dB = double(powerContext.PowerClosureError_dB);
row.PowerContextAmplitudeScale = double(powerContext.AmplitudeScale);
row.WaveformAmplitudeUnit = string(powerContext.WaveformAmplitudeUnit);
row.TxPowerSource = string(powerContext.TotalTxPowerSource);
row.TxRFExecutionStatus = string(sixgr.util.structGet( ...
    txRF.Replay,"RFExecutionStatus","applied_or_identity"));
row.TxRFStageOrder = string(sixgr.util.structGet(txRF.Replay,"RFStageOrder",""));
row.TxRFAppliedStageCount = double(sixgr.util.structGet( ...
    txRF.Replay,"RFAppliedStageCount",0));
stateField = "DLChannelState";
if direction == "UL"
    stateField = "ULChannelState";
end
chState = runtime.(stateField);
sharedTDD = sixgr.channel.ChannelFactory.supportsDynamicRuntimeTDDReciprocity(cfgStage);
if sharedTDD
    otherField = "ULChannelState";
    if direction == "UL"
        otherField = "DLChannelState";
    end
    otherState = runtime.(otherField);
    if logical(sixgr.util.structGet(otherState, "Initialized", false))
        if ~logical(sixgr.util.structGet(chState, "Initialized", false))
            chState = otherState;
        else
            if string(chState.StateKey) ~= string(otherState.StateKey) || ...
                    double(chState.Seed) ~= double(otherState.Seed)
                error("sixgr:phy:ra:InconsistentTDDChannelAuthority", ...
                    "Four-step TDD RA requires one canonical link state and seed for both directions.");
            end
            if double(otherState.CurrentSampleIndex) > double(chState.CurrentSampleIndex)
                chState = otherState;
            end
        end
    end
    if logical(sixgr.util.structGet(chState, "Initialized", false))
        chState = localStageChannelDirectionView(chState, cfgStage, direction, runtime);
    end
end
if ~(isstruct(chState) && isfield(chState, "ContractVersion") && logical(sixgr.util.structGet(chState, "Initialized", false)))
    linkKey = sixgr.channel.ChannelFactory.runtimeChannelKey(cfgStage, direction, ...
        "UEIndex", runtime.UEIndex, "ServingCell", runtime.ServingCell);
    chState = sixgr.channel.ChannelFactory.createRuntimeChannelState(cfgStage, direction, ...
        "LinkKey", linkKey, ...
        "Seed", sixgr.channel.ChannelFactory.runtimeChannelSeed(cfgStage, linkKey), ...
        "UEIndex", runtime.UEIndex, "ServingCell", runtime.ServingCell);
end
numTx = max(1, size(txWave, 2));
numRx = localResolveStageRxPorts(cfgStage, direction, numTx);
[txRuntimeAntenna, txRuntimeMeta] = localStageRuntimeAntenna( ...
    cfgStage, direction, "tx", numTx, string(row.StageName));
[rxRuntimeAntenna, rxRuntimeMeta] = localStageRuntimeAntenna( ...
    cfgStage, direction, "rx", numRx, string(row.StageName));
chState = sixgr.channel.ChannelFactory.materializeRuntimeChannelState(chState, cfgStage, ...
    txWave, txInfo, ...
    "NumTxAnt", numTx, "NumRxAnt", numRx, ...
    "TransmitAntennaRuntime", txRuntimeAntenna, ...
    "ReceiveAntennaRuntime", rxRuntimeAntenna, ...
    "TransmitAntennaMeta", txRuntimeMeta, ...
    "ReceiveAntennaMeta", rxRuntimeMeta);
slotStart_s = localStageSlotStartTime(cfgStage, double(row.StageSlot));
if isfinite(slotStart_s)
    chState = sixgr.channel.ChannelFactory.advanceRuntimeChannelStateToTime(chState, slotStart_s, numTx, txWave);
end
[rxWave, replay, chState] = sixgr.channel.ChannelFactory.applyRuntimeChannelState(chState, txWave);
runtime.(stateField) = chState;
if sharedTDD
    % These are directional views of one physical object, not independent
    % fading clocks. Publish the advanced counters with BOTH views before
