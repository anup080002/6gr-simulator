        ismatrix(rxWave) && all(isfinite(rxWave(:))))
    error("sixgr:phy:ra:BadRuntimeStageWaveform", ...
        "Runtime waveform %s for %s must be a finite floating-point sample-by-port matrix.", string(fieldName), string(stageName));
