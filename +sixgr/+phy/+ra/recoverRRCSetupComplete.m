function [rx, message] = recoverRRCSetupComplete( ...
        rxWaveform, cfg, raCfg, tx)
%RECOVERRRCSETUPCOMPLETE Decode UL-DCCH/SRB1 from PUSCH/UL-SCH at the gNB.
grant = tx.Grant;
cfgRx = sixgr.phy.ra.localizeRAPUSCHConfig(cfg, raCfg, grant, ...
    raCfg.SetupCompleteSlot, "RRCSetupComplete");
% An earlier TA command or channel trim is not a receiver timing estimate.
% Preserve PUSCH_Rx's explicit aligned-boundary bypass, otherwise acquire
% residual arrival from this actual UL-DCCH DM-RS observation.
[puschRx, info] = sixgr.phy.ul.PUSCH_Rx(rxWaveform, cfgRx, ...
    "Carrier", tx.Carrier, ...
    "PUSCH", tx.PUSCH, ...
    "TransportBlockSize", double(tx.TransportBlockSize), ...
    "TargetCodeRate", double(grant.TargetCodeRate), ...
    "RV", double(grant.RV), ...
    "InitialIMCSPerCodeword", double(grant.MCS), ...
    "ExecutionProfile", "ra_setup_complete");
rx = puschRx;
rx.Info = info;
if logical(puschRx.Ok)
    payloadBits = int8(puschRx.TransportBlock( ...
        1:double(tx.RRCSetupCompleteBitLength)));
    message = sixgr.mac.ra.parseRRCSetupComplete(payloadBits);
else
    message = struct();
end
end
