function evidence=receiverDiagnostics(rx)
% Compact, receiver-owned RA diagnostics; no TX/configuration truth input.
% Unknown numeric/boolean measurements remain NaN, including failed stages.
if nargin==0, rx=struct(); end
assert(isstruct(rx) && isscalar(rx),'sixgr:ra:ReceiverDiagnosticsShape', ...
    'RA diagnostics require one actual receiver result or an empty struct.');
evidence=struct('ReceiverDiagnosticsPresent',false, ...
    'ReceiverDiagnosticsSource',"no_receiver_diagnostics_in_stage_result");
numeric=["TimingEstimateUsed","RawTimingEstimate_samples","AppliedTimingCorrection_samples", ...
    "CFOEstimateAvailable","EstimatedCFO_Hz","EstimatedCommonFrequency_Hz", ...
    "CFOCorrectionApplied","CFOCorrectionApplied_Hz", ...
    "ResidualCFO_PostCorrection_Hz","ResidualCFO_EstimatedPostCorrection_Hz", ...
    "ResidualTimingError_PostCorrection_samples","ExpectedArrivalOffset_samples", ...
    "PostEqSINR_dB","ReceiverHestSINR_dB","PostEqSINRWidebanddB", ...
    "PostEqSINRRawEqualizer_dB","PostEqSINRDMRSResidual_dB","PostEqDecisionResidual_dB", ...
    "PostEqSINRDMRSResidualBoundApplied","PostEqSINRDecisionResidualBoundApplied", ...
    "PostEqSINRReceiverDerived","PostEqSINRAvailable", ...
    "PreEqualizationNoiseVar","DecoderNoiseVar","ChannelEstimateAvailable", ...
    "ChannelEstimatePilotResidualNMSE_dB","EqualizationAvailable", ...
    "LLRFinite","DemapperLLRCount","DecoderIterations"];
for name=numeric
    value=sixgr.util.structGet(rx,name,NaN);
    assert((isnumeric(value)||islogical(value)) && isreal(value) && isscalar(value), ...
        'sixgr:ra:ReceiverDiagnosticValue','Receiver diagnostic %s must be a real scalar.',name);
    evidence.(name)=double(value);
end
text=["TimingEstimateSource","TimingEstimateStatus","ResidualCFOEstimateSource", ...
    "TimingScoringReferenceSource","TimingScoringReferencePlane","TimingScoringReferenceJSON", ...
    "ReceiverTrackingCorrectionSource","ReceiverTrackingCorrectionStatus", ...
    "ReceiverTrackingCorrectionNAReason","ReceiverHestSINRSource", ...
    "ReceiverHestSINRValueRole","ReceiverHestSINRValueStatus","ReceiverHestSINRNAReason", ...
    "PostEqSINRSource","PostEqSINRValueRole","PostEqSINRValueStatus","PostEqSINRNAReason", ...
    "PostEqSINRRawReduction","PostEqDMRSResidualSource","PostEqDecisionResidualSource", ...
    "SINRComputationMethod","ChannelEstimateMethod","ChannelEstimatePilotResidualNMSESource"];
for name=text
    value=string(sixgr.util.structGet(rx,name,""));
    assert(isscalar(value),'sixgr:ra:ReceiverDiagnosticValue', ...
        'Receiver diagnostic %s must be scalar text.',name);
    evidence.(name)=value;
end
% A prepared/default struct with only Ok=false is not receiver evidence.
% This describes diagnostic-field presence, not decode attempt or success.
evidence.ReceiverDiagnosticsPresent=any(isfield(rx, ...
    [numeric,text,"CFOObservation","PostEqSINRPerLayer_dB"]));
if evidence.ReceiverDiagnosticsPresent
    evidence.ReceiverDiagnosticsSource="stage_receiver_output_diagnostics_not_a_CRC_or_attempt_claim";
end
evidence.PostEqSINRPerLayerJSON="";
if isfield(rx,'PostEqSINRPerLayer_dB')
    value=rx.PostEqSINRPerLayer_dB;
    assert(isnumeric(value) && isreal(value) && (isvector(value)||isempty(value)), ...
        'sixgr:ra:ReceiverDiagnosticValue','Preserve the actual per-layer SINR vector.');
    evidence.PostEqSINRPerLayerJSON=string(jsonencode(value));
end
% Reuse ordinary PDSCH/PUSCH CFO definitions, including whether a reported
% residual merely reuses the acquisition observation. Do not call it an
% independent post-correction estimator without that receiver evidence.
T=sixgr.link.addCFOObservationColumns(struct2table(evidence,'AsArray',true), ...
    {sixgr.util.structGet(rx,'CFOObservation',struct())},{rx});
evidence=table2struct(T);
end
