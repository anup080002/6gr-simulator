function prachCfg = buildPRACHConfigFromRACHCommon(cfg, raCfg)
%BUILDPRACHCONFIGFROMRACHCOMMON Resolve PRACH config from explicit RA config.
% The installed RACH-common operand owns frequency-domain occasions. Do not
% recover it from the scenario after the received/common context was built.
msg1FDM = sixgr.util.structGet(raCfg, "Msg1FDM", []);
if ~(isnumeric(msg1FDM) && isscalar(msg1FDM) && isfinite(msg1FDM) && ...
        any(msg1FDM == [1 2 4 8]))
    error("sixgr:phy:ra:InvalidRACHCommonMsg1FDM", ...
        "RACH-common Msg1FDM must explicitly specify 1, 2, 4 or 8 occasions.");
end
base = struct();
base.ScenarioName = char(raCfg.ScenarioName);
duplexMode = sixgr.phy.frame.resolveDuplexMode(cfg);
base.random_access = struct( ...
    "frequency_range", char(string(sixgr.util.structGet(cfg, "random_access.frequency_range", "FR1"))), ...
    "duplex_mode", char(duplexMode), ...
    "carrier_frequency_hz", double(sixgr.util.structGet(cfg, "random_access.carrier_frequency_hz", ...
        sixgr.util.structGet(cfg, "frequency.center_frequency_hz", 4e9))), ...
    "carrier_scs_khz", double(raCfg.CarrierSCSkHz), ...
    "n_size_grid", double(raCfg.NSizeGrid), ...
    "configuration_index", double(raCfg.PRACHConfigurationIndex), ...
    "prach_format", char(raCfg.PRACHFormat), ...
    "subcarrier_spacing_khz", double(raCfg.PRACHSubcarrierSpacing), ...
    "root_sequence_index", double(raCfg.RootSequenceIndex), ...
    "zero_correlation_zone", double(raCfg.ZeroCorrelationZoneConfig), ...
    "restricted_set", char(raCfg.RestrictedSetType), ...
    "frequency_start", double(raCfg.FrequencyStart), ...
    "msg1_fdm", double(msg1FDM), ...
    "preamble_index", double(raCfg.PreambleIndex), ...
    "num_tx_antennas", double(sixgr.util.structGet(cfg, "random_access.num_tx_antennas", 1)), ...
    "num_prach_occasions", 1, ...
    "num_slots", max(1, double(raCfg.PRACHOccasionSlot) + 1), ...
    "detection_threshold", double(sixgr.util.structGet(cfg, "random_access.detection_threshold", 0.02)), ...
    "detection_threshold_mode", char(string(sixgr.util.structGet(cfg, "random_access.detection_threshold_mode", "fixed"))), ...
    "enable_frequency_estimation_metric", logical(sixgr.util.structGet( ...
        cfg, "random_access.enable_frequency_estimation_metric", false)));
base.phy.carrier.NCellID = double(raCfg.NCellID);
if isfield(cfg.random_access,'target_false_alarm_probability')
    base.random_access.target_false_alarm_probability=cfg.random_access.target_false_alarm_probability;
end
base.phy.carrier.NSizeGrid = double(raCfg.NSizeGrid);
base.phy.carrier.SubcarrierSpacing = double(raCfg.CarrierSCSkHz);
base.phy.duplex.mode = char(duplexMode);
base.channel.model = char(localResolvePRACHChannelModel(cfg));
base.channel.awgnOnly = logical(sixgr.util.structGet(cfg, "channel.awgnOnly", strcmpi(base.channel.model, "AWGN")));
prachCfg = sixgr.rach.PRACHConfig(base, ...
    "PreambleIndex", double(raCfg.PreambleIndex), ...
    "PRACHConfigurationIndex", double(raCfg.PRACHConfigurationIndex), ...
    "PRACHFormat", char(raCfg.PRACHFormat), ...
    "PRACHSubcarrierSpacing", double(raCfg.PRACHSubcarrierSpacing), ...
    "SequenceIndex", double(raCfg.RootSequenceIndex), ...
    "ZeroCorrelationZone", double(raCfg.ZeroCorrelationZoneConfig), ...
    "FrequencyStart", double(raCfg.FrequencyStart), ...
    "Msg1FDM", double(msg1FDM), ...
    "NSizeGrid", double(raCfg.NSizeGrid), ...
    "CarrierSCSkHz", double(raCfg.CarrierSCSkHz), ...
    "RestrictedSet", char(raCfg.RestrictedSetType), ...
    "NumTxAntennas", double(base.random_access.num_tx_antennas), ...
    "NumPRACHOccasions", 1, ...
    "NumSlots", max(1, double(raCfg.PRACHOccasionSlot) + 1), ...
    "EnableFrequencyEstimationMetric", logical(base.random_access.enable_frequency_estimation_metric), ...
    "ChannelModel", base.channel.model);
end

function model = localResolvePRACHChannelModel(cfg)
model = string(sixgr.util.structGet(cfg, "random_access.channel_model", ""));
if strlength(strtrim(model)) == 0
    model = string(sixgr.util.structGet(cfg, "prach_lls.ChannelModel", ""));
end
if strlength(strtrim(model)) == 0
    model = string(sixgr.util.structGet(cfg, "channel.model", ""));
end
if strlength(strtrim(model)) == 0
    model = string(sixgr.util.structGet(cfg, "channel.tdlProfile", ""));
end
if strlength(strtrim(model)) == 0
    model = string(sixgr.util.structGet(cfg, "channel.cdlProfile", "AWGN"));
end
token = upper(strtrim(model));
if token == "TDL"
    concrete = string(sixgr.util.structGet(cfg, "channel.tdlProfile", ""));
    if strlength(strtrim(concrete)) > 0
        token = upper(strtrim(concrete));
    end
elseif token == "CDL"
    concrete = string(sixgr.util.structGet(cfg, "channel.cdlProfile", ""));
    if strlength(strtrim(concrete)) > 0
        token = upper(strtrim(concrete));
    end
end
model = token;
end
