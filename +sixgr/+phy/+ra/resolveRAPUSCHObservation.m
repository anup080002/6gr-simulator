function [waveform,args,receipt]=resolveRAPUSCHObservation(input,carrier,pusch,stage)
% Keep the original completed RA receive buffer through DM-RS acquisition.
% Numeric-array callers retain their existing standalone receiver policy.
waveform=input; args={}; receipt=struct();
if ~isa(input,'sixgr.phy.waveform.WaveformObservationBuffer'), return; end
assert(isscalar(input) && any(string(stage)==["Msg3","RRCSetupComplete"]), ...
    'sixgr:phy:ra:InvalidRAPUSCHObservation','Use one actual RA PUSCH capture.');
waveform=input.readComplete();
info=nrOFDMInfo(carrier); fs=double(info.SampleRate);
slot0=double(carrier.NFrame)*double(carrier.SlotsPerFrame)+double(carrier.NSlot);
nominal=sixgr.phy.frame.slotStartSample(carrier,slot0,fs);
stop=sixgr.phy.frame.slotStartSample(carrier,slot0+1,fs);
assert(input.SampleRateHz==fs && input.StartSample<=nominal && ...
    input.EndSampleExclusive>nominal && size(waveform,1)>=stop-nominal, ...
    'sixgr:phy:ra:RAPUSCHObservationClockMismatch', ...
    'The original capture must contain a complete scheduled-slot FFT interval.');
args={'TimingSearchWindowSamples',[0 size(waveform,1)-(stop-nominal)]};
receipt=struct('ContractVersion',"received_RA_PUSCH_timing/v1", ...
    'Stage',string(stage),'RNTI',double(pusch.RNTI),'NCellID',double(carrier.NCellID), ...
    'SCSkHz',double(carrier.SubcarrierSpacing),'NSizeGrid',double(carrier.NSizeGrid), ...
    'NStartGrid',double(carrier.NStartGrid),'CyclicPrefix',string(carrier.CyclicPrefix), ...
    'AbsoluteSlot0',slot0,'NominalStartSample',nominal, ...
    'ObservationStartSample',input.StartSample,'AvailableAtSample',input.EndSampleExclusive, ...
    'SampleRateHz',fs,'InputSampleSHA256',sixgr.phy.waveform.WaveformHash.numeric(waveform));
end
