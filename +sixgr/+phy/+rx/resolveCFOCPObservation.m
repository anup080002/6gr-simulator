function policy=resolveCFOCPObservation(cfg)
% Explicit YAML receiver policy; old direct-PHY configurations retain full CP.
policy=sixgr.util.structGet(cfg,'phy.impairments.cfoCPObservation',struct());
source=sixgr.util.structGet(cfg,'lls6g.resolvedConfig.impairments',struct());
if isfield(source,'cfo_cp_observation_policy')
    assert(isstruct(policy) && isscalar(policy) && ...
        all(isfield(policy,{'Policy','WindowFraction','FalseAlarmProbability'})) && ...
        string(policy.Policy)==string(source.cfo_cp_observation_policy) && ...
        isequal(policy.WindowFraction,double(source.cfo_cp_window_fraction)) && ...
        isequal(policy.FalseAlarmProbability,double(source.cfo_cp_false_alarm_probability)), ...
        'sixgr:phy:rx:CFOCPPolicyAuthorityMismatch', ...
        'Cyclic-prefix receiver observation policy must match installed YAML.');
end
end
