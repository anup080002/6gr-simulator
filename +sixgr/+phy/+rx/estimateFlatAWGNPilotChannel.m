function out=estimateFlatAWGNPilotChannel(received,reference)
% Fit one constant complex gain per RX branch to known reference symbols.
% Receiver-only least squares for an explicitly flat, static AWGN model.
% Caller must establish that model; never expand these coefficients into
% a fading-channel Hest. No channel truth, injected variance or SNR input.
assert(isfloat(received) && ismatrix(received) && size(received,1)>1 && ...
    size(received,2)>=1 && all(isfinite(received),'all') && ...
    isfloat(reference) && iscolumn(reference) && ...
    numel(reference)==size(received,1) && all(isfinite(reference)), ...
    'sixgr:phy:rx:InvalidFlatAWGNPilots', ...
    'Require finite N-by-R samples and N-by-1 reference symbols, N>1.');
energy=sum(abs(reference).^2);
assert(isfinite(energy) && energy>0, ...
    'sixgr:phy:rx:InvalidFlatAWGNReferenceEnergy', ...
    'Do not fit a zero-energy or unrepresentable reference.');
gain=(reference'*received)/energy;
residual=received-reference*gain;
% Each branch fitted one complex coefficient: N-1 complex residual DOFs.
dof=size(received,1)-1;
noiseByBranch=sum(abs(residual).^2,1)/dof;
assert(all(isfinite(gain)) && all(isfinite(noiseByBranch)), ...
    'sixgr:phy:rx:InvalidFlatAWGNFit','Do not hide arithmetic overflow.');
out=struct('GainPerReceiveBranch',gain, ...
    'NoiseVariancePerReceiveBranch',noiseByBranch, ...
    'NoiseVariance',mean(noiseByBranch), ...
    'CoefficientErrorVarianceEstimatePerReceiveBranch',noiseByBranch/energy, ...
    'ReferenceEnergy',energy,'PilotCount',size(received,1), ...
    'ResidualComplexDegreesOfFreedomPerBranch',dof, ...
    'Source',"received_known_pilot_flat_static_least_squares", ...
    'NoiseVariancePlane',"received_pilot_RE_per_receive_branch", ...
    'ModelAssumption',"constant_gain_per_receive_branch_with_additive_white_noise", ...
    'UsedScoringReference',false);
end
