function score=squaredGeneralizedCosineSimilarity(estimate,reference)
% Paired-vector SGCS. This is not a channel condition number, PMI accuracy,
% or a claim about a particular CSI compression evaluation template.
% Flatten corresponding values in MATLAB column order; no phase/gain fit,
% nonfinite-value removal, truncation, or zero-denominator substitution.
assert(isnumeric(estimate) && isnumeric(reference) && ...
    isequal(size(estimate),size(reference)) && ~isempty(estimate) && ...
    all(isfinite(estimate(:))) && all(isfinite(reference(:))), ...
    'sixgr:phy:InvalidSGCSPairs','SGCS requires complete, identically shaped finite paired values.');
h=double(estimate(:)); r=double(reference(:));
eh=sum(abs(h).^2); er=sum(abs(r).^2); inner=sum(conj(r).*h);
assert(isfinite(eh) && isfinite(er) && isfinite(inner), ...
    'sixgr:phy:InvalidSGCSEnergy','SGCS operands must have representable finite energies.');
score=struct('Value',NaN,'Available',false, ...
    'Status',"undefined_zero_vector_energy", ...
    'Definition',"abs(reference_H_estimate)^2/(reference_energy*estimate_energy)", ...
    'EstimateEnergy',eh,'ReferenceEnergy',er, ...
    'InnerProductReal',real(inner),'InnerProductImag',imag(inner), ...
    'ComparedValues',numel(h),'GainOrPhaseFitted',false, ...
    'MissingValuesDiscarded',false);
if eh==0 || er==0, return; end
% Normalize vectors before the inner product to avoid squaring a large
% unnormalized product or multiplying two small denominator energies.
value=abs(sum(conj(r/sqrt(er)).*(h/sqrt(eh))))^2;
assert(isfinite(value) && value>=0 && value<=1+256*eps, ...
    'sixgr:phy:InvalidSGCSRange','Paired-vector SGCS violates the Cauchy-Schwarz bound.');
score.Value=min(value,1); % Only floating-point excess above the exact bound.
score.Available=true;
score.Status="measured_paired_vector_similarity";
end
