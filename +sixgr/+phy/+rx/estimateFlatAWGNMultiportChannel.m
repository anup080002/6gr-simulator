function out=estimateFlatAWGNMultiportChannel(received,reference)
% Joint practical LS from N-by-R observations and N-by-P known pilots.
% Valid model: a constant complex P-by-R channel over these pilot REs with
% additive white noise. The caller must explicitly establish that model.
% This function neither selects a model nor expands a fading-channel grid.
% No scoring channel, transmitted payload, injected noise or SNR is accepted.
assert(isfloat(received) && ismatrix(received) && size(received,2)>=1 && ...
    isfloat(reference) && ismatrix(reference) && size(reference,2)>=1 && ...
    strcmp(class(received),class(reference)) && ...
    size(received,1)==size(reference,1) && ...
    size(reference,1)>size(reference,2) && ...
    all(isfinite(received),'all') && all(isfinite(reference),'all'), ...
    'sixgr:phy:rx:InvalidFlatMultiportPilots', ...
    'Require finite, same-precision N-by-R observations and N-by-P pilots, N>P.');
[Q,T]=qr(reference,0);
singularValues=svd(T);
assert(all(isfinite(singularValues)) && singularValues(1)>0 && ...
    singularValues(end)>max(size(reference))*eps(singularValues(1)), ...
    'sixgr:phy:rx:UnidentifiableFlatMultiportChannel', ...
    'Configured pilots must identify every port; no pseudoinverse or dropped ports.');
gain=T\(Q'*received);
fitted=reference*gain;
residual=received-fitted;
dof=size(reference,1)-size(reference,2);
noisePerBranch=sum(abs(residual).^2,1)/dof;
% Cov(hhat_r)=sigma_r^2*(X''*X)^(-1), evaluated with triangular solves.
inverseT=T\eye(size(T),'like',T);
unitNoiseCovariance=inverseT*inverseT';
variancePerPortBranch=real(diag(unitNoiseCovariance))*noisePerBranch;
% Fitting P complex coefficients projects P noise dimensions into the
% reconstructed signal. E(||X*hhat||^2)=||X*h||^2+P*sigma^2. Correct this
% in POWER, retaining its signed result, not by shifting an exported dB.
N=size(reference,1); P=size(reference,2);
rawPower=mean(abs(fitted).^2,1);
noiseBias=(P/N)*noisePerBranch;
signedPower=rawPower-noiseBias;
% Dividing unbiased power by estimated noise is itself biased. For d=N-P
% complex residual degrees of freedom, E(1/sigmahat^2)=d/((d-1)*sigma^2).
% The correction below is unbiased in LINEAR SNR for d>1. log10 and branch
% selection are nonlinear: neither their result nor a clipped value is
% claimed to be an unbiased measurement.
signedSNR=nan(size(noisePerBranch));
ratioStatus=repmat("unavailable_insufficient_residual_degrees_of_freedom",size(noisePerBranch));
if dof>1
    positiveNoise=noisePerBranch>0;
    signedSNR(positiveNoise)=((dof-1)/dof)* ...
        (rawPower(positiveNoise)./noisePerBranch(positiveNoise))-P/N;
    ratioStatus(:)="unavailable_zero_estimated_disturbance";
    ratioStatus(positiveNoise)="signed_unbiased_linear_ratio_not_dB_or_detected_signal";
end
% Under noise only, fitted and residual energies are independent complex
% chi-square components: F has real degrees (2P,2d). Compute its survival
% probability with base-MATLAB betainc; no Statistics Toolbox dependency.
fittedEnergy=N*rawPower; residualEnergy=dof*noisePerBranch;
noiseOnlyP=nan(size(noisePerBranch));
hasEnergy=fittedEnergy+residualEnergy>0;
noiseOnlyP(hasEnergy)=betainc(residualEnergy(hasEnergy)./ ...
    (fittedEnergy(hasEnergy)+residualEnergy(hasEnergy)),dof,P);
powerMeasurement=struct('ContractVersion',"FlatPilotPower/v1", ...
    'RawReconstructedPowerPerReceiveBranch',rawPower, ...
    'EstimatedNoiseBiasPerReceiveBranch',noiseBias, ...
    'SignedSignalPowerPerReceiveBranch',signedPower, ...
    'NoisePowerPerReceiveBranch',noisePerBranch, ...
    'SignedReferenceSNRLinearPerReceiveBranch',signedSNR, ...
    'ReferenceSNRStatusPerReceiveBranch',ratioStatus, ...
    'NoiseOnlyNullTailProbabilityPerReceiveBranch',noiseOnlyP, ...
    'PilotCount',N,'FittedComplexParametersPerBranch',P, ...
    'ResidualComplexDegreesOfFreedomPerBranch',dof, ...
    'Source',"received_known_pilot_LS_projection_and_residual_degrees_of_freedom", ...
    'Scope',"constant_multiport_channel_white_complex_gaussian_noise", ...
    'ClippedToNonnegative',false,'ConfiguredSNROrChannelTruthUsed',false);
assert(all(isfinite(gain),'all') && all(isfinite(noisePerBranch)) && ...
    all(isfinite(variancePerPortBranch),'all'), ...
    'sixgr:phy:rx:InvalidFlatMultiportFit','Do not hide arithmetic overflow.');
out=struct('GainPerPortReceiveBranch',gain, ...
    'NoiseVariancePerReceiveBranch',noisePerBranch, ...
    'NoiseVariance',mean(noisePerBranch), ...
    'CoefficientErrorVarianceEstimatePerPortReceiveBranch',variancePerPortBranch, ...
    'UnbiasedCoefficientPowerEstimatePerPortReceiveBranch',abs(gain).^2-variancePerPortBranch, ...
    'ReferencePowerMeasurement',powerMeasurement, ...
    'UnitNoiseCoefficientCovariance',unitNoiseCovariance, ...
    'PilotCount',size(reference,1),'NumReferencePorts',size(reference,2), ...
    'ResidualComplexDegreesOfFreedomPerBranch',dof, ...
    'ReferenceConditionNumber',singularValues(1)/singularValues(end), ...
    'Source',"received_known_pilot_flat_static_joint_least_squares", ...
    'NoiseVariancePlane',"received_pilot_RE_per_receive_branch", ...
    'ModelAssumption',"constant_multiport_channel_with_additive_white_noise", ...
    'UsedScoringReference',false);
end
