function [options,evidence]=channelEstimateWienerOptions(toolboxVersion)
% Public API contract only; the caller supplies its actual ver('5g').Version.
% R2024a nrChannelEstimate always interpolates and exposes only CyclicPrefix,
% CDMLengths and AveragingWindow. Interpolation was added in R2025a (25.1).
% This does not probe/retry the receiver or substitute another estimator.
versionText=string(toolboxVersion);
assert(isscalar(versionText) && ~ismissing(versionText) && ...
    ~isempty(regexp(char(versionText),'^\d+\.\d+(\.\d+)*$','once')), ...
    'sixgr:phy:channelEstimate:InvalidToolboxVersion', ...
    'Use the installed numeric 5G Toolbox version, not an inferred MATLAB release.');
parts=sscanf(char(versionText),'%d.');
assert(numel(parts)>=2 && all(isfinite(parts)) && all(parts>=0), ...
    'sixgr:phy:channelEstimate:InvalidToolboxVersion','Invalid 5G Toolbox version.');
hasOption=parts(1)>25 || (parts(1)==25 && parts(2)>=1);
options={'AveragingWindow',[0 0]};
policy="legacy_native_always_interpolating_API";
if hasOption
    options=[{'Interpolation','on'},options];
    policy="explicit_public_interpolation_on";
end
evidence=struct('Operator',"nrChannelEstimate", ...
    'FiveGToolboxVersion',versionText,'InterpolationMode',"on", ...
    'InterpolationOptionForwarded',logical(hasOption), ...
    'InterpolationOptionIntroducedToolboxVersion',"25.1", ...
    'AppliedAveragingWindow',[0 0],'Policy',policy, ...
    'Authority',"documented_public_5G_Toolbox_version", ...
    'LegacyReference',"https://www.mathworks.com/help/releases/R2024a/5g/ref/nrchannelestimate.html", ...
    'VersionHistoryReference',"https://www.mathworks.com/help/5g/ref/nrchannelestimate.html");
end
