function [corrected,evidence]=applyControlFrequencyCorrection(waveform,carrier,cfg,symbolIndices0Based)
% Actual timing-aligned control capture -> fractional common-frequency RX.
% CP correlation is an implementation algorithm, not a prescribed NR method.
% No transmitted payload, injected CFO, channel truth or opposite-direction
% state is an input. The local sample origin is the aligned capture start.
enabled=sixgr.util.structGet(cfg,'phy.rx.cfoCorrectionEnabled', ...
    sixgr.util.structGet(cfg,'phy.impairments.cfoCorrectionEnabled',false));
assert((islogical(enabled)||isnumeric(enabled)) && isscalar(enabled) && ...
    isreal(enabled) && isfinite(enabled) && any(enabled==[0 1]), ...
    'sixgr:phy:rx:ControlFrequencyPolicy','Declare a boolean CFO correction policy.');
sampling=sixgr.phy.frame.OFDMSamplingResolver.resolve(carrier);
ofdm=sampling.ToolboxOFDMInfo;
ofdm.OFDMSamplingResolution=sampling;
policy=sixgr.phy.rx.resolveCFOCPObservation(cfg);
policy.SymbolIndices0Based=symbolIndices0Based;
method=lower(strtrim(string(sixgr.util.structGet(cfg,'phy.impairments.cfoEstimationMethod','cyclic_prefix'))));
assert(isscalar(method) && (~enabled || any(method==["cyclic_prefix","cp"])), ...
    'sixgr:phy:rx:UnsupportedControlFrequencyMethod', ...
    'Control-frequency compensation currently supports cyclic_prefix/cp; do not silently substitute another configured estimator.');
corrected=waveform;
evidence=struct('CFOCorrectionEnabled',logical(enabled), ...
    'CFOEstimateAvailable',false,'EstimatedCFO_Hz',NaN, ...
    'EstimatedCommonFrequency_Hz',NaN, ...
    'FrequencyEstimateDomain',"received_common_frequency_not_oscillator_only", ...
    'CFOEstimateSource',"received_configured_control_symbols_cyclic_prefix", ...
    'CFOCorrectionApplied',false,'CFOCorrectionApplied_Hz',NaN, ...
    'CFOCorrectionSource',"not_applied",'CFOCorrectionSampleOrigin',0, ...
    'CorrectionSign',-1,'CorrectionSampleCount',size(waveform,1), ...
    'SampleRateHz',sampling.SampleRateHz, ...
    'CorrectionSampleDomain',"relative_to_timing_aligned_receiver_input_zero_based", ...
    'CFOCorrectionClockSource',"timing_aligned_receiver_input_local_sample_zero", ...
    'AlignedInputSHA256',sixgr.phy.waveform.WaveformHash.numeric(waveform), ...
    'CorrectedInputSHA256',"",'Status',"disabled_by_receiver_configuration", ...
    'CFOObservation',struct(),'ResidualCFOObservation',struct(), ...
    'ResidualCFOEstimateAvailable',false,'ResidualCFOEstimatorConsistency_Hz',NaN, ...
    'ResidualCFOReusesAcquisitionObservation',false, ...
    'ResidualCFOEstimateRole',"not_measured");
if enabled
    [hz,measurement]=sixgr.phy.rx.estimateCFOFromCyclicPrefix( ...
        waveform,ofdm,sampling.SampleRateHz,policy);
    evidence.CFOObservation=measurement;
    evidence.Status=string(measurement.Status);
    evidence.CFOEstimateAvailable=measurement.EstimateAvailable;
    if measurement.EstimateAvailable
        assert(isscalar(hz)&&isfinite(hz),'sixgr:phy:rx:InvalidControlFrequencyEstimate', ...
            'Available frequency evidence must be finite.');
        evidence.EstimatedCFO_Hz=hz;
        evidence.EstimatedCommonFrequency_Hz=hz;
        phase=exp(-2i*pi*hz/sampling.SampleRateHz*(0:size(waveform,1)-1).');
        corrected=waveform.*cast(phase,'like',waveform);
        evidence.CFOCorrectionApplied=true;
        evidence.CFOCorrectionApplied_Hz=hz;
        evidence.CFOCorrectionSource=evidence.CFOEstimateSource;
        [residual,residualInfo]=sixgr.phy.rx.estimateCFOFromCyclicPrefix( ...
            corrected,ofdm,sampling.SampleRateHz,policy);
        evidence.ResidualCFOObservation=residualInfo;
        evidence.ResidualCFOEstimateAvailable=residualInfo.EstimateAvailable;
        if residualInfo.EstimateAvailable
            evidence.ResidualCFOEstimatorConsistency_Hz=residual;
        end
        evidence.ResidualCFOReusesAcquisitionObservation=true;
        evidence.ResidualCFOEstimateRole="same_observation_estimator_consistency_not_independent_residual";
    end
end
evidence.CorrectedInputSHA256=sixgr.phy.waveform.WaveformHash.numeric(corrected);
end
