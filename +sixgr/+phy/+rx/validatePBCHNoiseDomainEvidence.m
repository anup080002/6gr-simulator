function validatePBCHNoiseDomainEvidence(pb)
%VALIDATEPBCHNOISEDOMAINEVIDENCE Enforce PBCH same-plane SINR evidence.

required = [ ...
    "PreEqualizationNoiseVariance", ...
    "PreEqualizationNoiseVarianceDomain", ...
    "PreEqualizationNoiseVarianceSource", ...
    "PostEqualizationNoiseVariance", ...
    "PostEqualizationNoiseVarianceDomain", ...
    "PostEqualizationNoiseVarianceSource", ...
    "PostEqSINR_dB", "PostEqSINRAvailable", ...
    "PostEqSINRValueStatus"];
for name = required
    if ~isfield(pb, char(name))
        error("sixgr:phy:pbch:MissingNoiseDomainEvidence", ...
            "PBCH strict evidence is missing %s.", name);
    end
end

preVariance = double(pb.PreEqualizationNoiseVariance);
postVariance = double(pb.PostEqualizationNoiseVariance);
postSINR = double(pb.PostEqSINR_dB);
available = logical(pb.PostEqSINRAvailable);
status = upper(strtrim(string(pb.PostEqSINRValueStatus)));

if available
    if ~(isscalar(preVariance) && isfinite(preVariance) && preVariance > 0 && ...
            isscalar(postVariance) && isfinite(postVariance) && postVariance > 0 && ...
            isscalar(postSINR) && isfinite(postSINR))
        error("sixgr:phy:pbch:InvalidNoiseDomainEvidence", ...
            "Available PBCH post-equalization SINR requires finite positive pre/post noise variances.");
    end
    expectedSINR = -10 * log10(postVariance);
    tolerance = max(1e-10, 64 * eps(max(abs(expectedSINR), 1)));
    if abs(postSINR - expectedSINR) > tolerance
        error("sixgr:phy:pbch:MixedNoiseDomainEvidence", ...
            ["PBCH PostEqSINR_dB %.15g is inconsistent with the same-plane " + ...
            "post-equalization noise variance %.15g (expected %.15g dB)."], ...
            postSINR, postVariance, expectedSINR);
    end
    if ~any(status == ["OK", "LOWER_BOUND_NOISE_FLOOR"])
        error("sixgr:phy:pbch:InvalidSINRAvailabilityStatus", ...
            "Available PBCH post-equalization SINR has invalid status %s.", status);
    end
else
    if isfinite(postSINR) || status == "OK"
        error("sixgr:phy:pbch:InvalidSINRAvailabilityStatus", ...
            "Unavailable PBCH post-equalization SINR cannot be finite or carry status OK.");
    end
end

if string(pb.PreEqualizationNoiseVarianceDomain) ~= ...
        "resource_grid_pre_equalization_per_receive_branch"
    error("sixgr:phy:pbch:MixedNoiseDomainEvidence", ...
        "PBCH pre-equalization noise variance has an unsupported reference domain.");
end
if string(pb.PostEqualizationNoiseVarianceDomain) ~= ...
        "unit_energy_pbch_symbol_post_equalization"
    error("sixgr:phy:pbch:MixedNoiseDomainEvidence", ...
        "PBCH post-equalization noise variance has an unsupported reference domain.");
end
if strlength(strtrim(string(pb.PreEqualizationNoiseVarianceSource))) == 0 || ...
        (available && strlength(strtrim(string( ...
        pb.PostEqualizationNoiseVarianceSource))) == 0)
    error("sixgr:phy:pbch:MissingNoiseDomainEvidence", ...
        "PBCH strict noise evidence requires nonblank variance sources.");
end
end
