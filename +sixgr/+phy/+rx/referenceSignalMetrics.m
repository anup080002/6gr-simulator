function metrics = referenceSignalMetrics(rxGrid, hEst, refInd, refSym, varargin)
%REFERENCESIGNALMETRICS Port-aware received-reference reconstruction metrics.
%
% The metric uses only the received grid, the receiver channel estimate,
% and known reference symbols. It does not consume a perfect/true channel.

ip = inputParser;
ip.FunctionName = "sixgr.phy.rx.referenceSignalMetrics";
ip.addParameter("NoiseVariance", NaN, ...
    @(x) isnumeric(x) && isscalar(x));
ip.addParameter("ContextLabel", "reference_signal", ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));
ip.parse(varargin{:});
nVar = double(ip.Results.NoiseVariance);

if ~(isnumeric(rxGrid) && isnumeric(hEst) && ...
        isnumeric(refInd) && isnumeric(refSym)) || ...
        isempty(rxGrid) || isempty(hEst) || ...
        isempty(refInd) || isempty(refSym)
    error("sixgr:phy:rx:ReferenceMetricInputMissing", ...
        "Received grid, Hest, reference indices, and symbols are required.");
end
K = size(rxGrid, 1);
L = size(rxGrid, 2);
R = max(1, size(rxGrid, 3));
P = max(1, size(hEst, 4));
if size(hEst, 1) ~= K || size(hEst, 2) ~= L || ...
        max(1, size(hEst, 3)) ~= R
    error("sixgr:phy:rx:ReferenceMetricGridShapeMismatch", ...
        "Hest grid %s is incompatible with received grid %s.", ...
        mat2str(size(hEst)), mat2str(size(rxGrid)));
end
if numel(refInd) ~= numel(refSym)
    error("sixgr:phy:rx:ReferenceMetricReferenceShapeMismatch", ...
        "Reference indices and symbols must contain the same entry count.");
end

indices = double(refInd(:));
symbols = double(refSym(:));
gridRE = double(K) * double(L);
if any(~isfinite(indices) | indices ~= fix(indices) | indices < 1 | ...
        indices > gridRE * double(P))
    error("sixgr:phy:rx:ReferenceMetricIndexOutOfRange", ...
        "Reference indices must be 1-based linear indices within K*L*P.");
end
physical = mod(indices - 1, gridRE) + 1;
ports = floor((indices - 1) ./ gridRE) + 1;
[physicalUnion, ~] = unique(physical, "stable");
[present, unionRow] = ismember(physical, physicalUnion);
if ~all(present)
    error("sixgr:phy:rx:ReferenceMetricUnionFailure", ...
        "Unable to resolve the stable physical reference-RE union.");
end

referenceMatrix = complex(zeros(numel(physicalUnion), P));
occupied = false(numel(physicalUnion), P);
for i = 1:numel(indices)
    row = unionRow(i);
    port = ports(i);
    if occupied(row, port)
        if abs(referenceMatrix(row, port) - symbols(i)) > ...
                64 * eps(max(1, abs(symbols(i))))
            error("sixgr:phy:rx:ReferenceMetricConflictingDuplicate", ...
                "Physical RE %d port %d has conflicting reference symbols.", ...
                physicalUnion(row), port - 1);
        end
        continue;
    end
    referenceMatrix(row, port) = symbols(i);
    occupied(row, port) = true;
end

rxFlat = reshape(double(rxGrid), gridRE, R);
hFlat = reshape(double(hEst), gridRE, R, P);
observed = rxFlat(physicalUnion, :);
hReference = hFlat(physicalUnion, :, :);
reconstructed = complex(zeros(numel(physicalUnion), R));
for port = 1:P
    reconstructed = reconstructed + ...
        hReference(:, :, port) .* referenceMatrix(:, port);
end

validRows = any(abs(referenceMatrix) > sqrt(eps), 2) ...
    & all(isfinite(real(observed)) & isfinite(imag(observed)), 2) ...
    & all(isfinite(real(reconstructed)) ...
        & isfinite(imag(reconstructed)), 2);
if ~any(validRows)
    error("sixgr:phy:rx:ReferenceMetricNoFiniteObservation", ...
        "No finite physical reference observations are available.");
end
observedValid = observed(validRows, :);
reconstructedValid = reconstructed(validRows, :);
residualValid = observedValid - reconstructedValid;
signalPower = mean(abs(reconstructedValid).^2, "all", "omitnan");
residualPower = mean(abs(residualValid).^2, "all", "omitnan");
if ~(isfinite(signalPower) && signalPower > 0 && ...
        isfinite(residualPower) && residualPower >= 0)
    error("sixgr:phy:rx:ReferenceMetricPowerUnavailable", ...
        "Reference reconstruction did not yield finite signal/residual power.");
end
if ~(isfinite(nVar) && nVar >= 0)
    nVar = NaN;
end
effectiveDisturbance = residualPower;
if isfinite(nVar)
    effectiveDisturbance = max(effectiveDisturbance, nVar);
end
effectiveDisturbance = max(effectiveDisturbance, eps);
nmse = residualPower ./ max(signalPower, eps);
sinr = signalPower ./ effectiveDisturbance;

perRESignal = mean(abs(reconstructed).^2, 2, "omitnan");
perREResidual = mean(abs(observed - reconstructed).^2, 2, "omitnan");
perREDisturbance = perREResidual;
if isfinite(nVar)
    perREDisturbance = max(perREDisturbance, nVar);
end
perRESINR = perRESignal ./ max(perREDisturbance, eps);
[subcarrier, symbolIndex] = ind2sub([K L], physicalUnion);

metrics = struct( ...
    "ContractVersion", "ReceiverReferenceSignalMetrics/v1", ...
    "Passed", true, ...
    "ContextLabel", string(ip.Results.ContextLabel), ...
    "Source", "received_reference_grid_plus_receiver_hest", ...
    "ValueRole", ...
        "dmrs_pilot_reconstruction_residual_without_true_channel_oracle", ...
    "PhysicalREOrdering", "stable_union_of_port_domain_linear_indices", ...
    "ReferenceIndexBase", "1based", ...
    "ReferenceEntryCount", double(numel(indices)), ...
    "PhysicalRECount", double(numel(physicalUnion)), ...
    "ReferencePortCount", double(P), ...
    "RxAntennaCount", double(R), ...
    "PhysicalLinearIndices", double(physicalUnion(:)), ...
    "SubcarrierIndices", double(subcarrier(:)), ...
    "SymbolIndices", double(symbolIndex(:)), ...
    "ReferenceMatrix", referenceMatrix, ...
    "ChannelAtReference", hReference, ...
    "ObservedSymbols", observed, ...
    "ReconstructedSymbols", reconstructed, ...
    "ResidualSymbols", observed - reconstructed, ...
    "ValidRowMask", logical(validRows), ...
    "SignalPower", double(signalPower), ...
    "ResidualPower", double(residualPower), ...
    "NoiseVariance", double(nVar), ...
    "EffectiveDisturbancePower", double(effectiveDisturbance), ...
    "NMSELinear", double(nmse), ...
    "NMSEdB", double(10 * log10(max(nmse, eps))), ...
    "SINRLinear", double(sinr), ...
    "SINRdB", double(10 * log10(max(sinr, eps))), ...
    "PerRESignalPower", double(perRESignal), ...
    "PerREResidualPower", double(perREResidual), ...
    "PerREEffectiveDisturbancePower", double(perREDisturbance), ...
    "PerRESINRdB", double(10 * log10(max(perRESINR, eps))), ...
    "Status", "PASS");
end
