function binding = resolveDLQCLTCIBinding(cfg)
%RESOLVEDLQCLTCIBINDING Normalize the installed DL QCL/TCI authority.
% Keep this file ASCII-only.

if nargin < 1 || ~isstruct(cfg)
    cfg = struct();
end

binding = struct( ...
    "ContractVersion", "sixgr_dl_qcl_tci_binding/v1", ...
    "Available", false, ...
    "ActiveTCIStateID", NaN, ...
    "TCICodepoint", NaN, ...
    "SpatialSourceResourceID", NaN, ...
    "SpatialSourceReferenceSignal", "", ...
    "ActivationAbsoluteSlot0", NaN, ...
    "InitializationSource", "", ...
    "QCL", struct(), ...
    "Digest", "");

qcl = sixgr.util.structGet(cfg, "phy.pdsch.qclTCI", struct());
if ~(isstruct(qcl) && isscalar(qcl) && ~isempty(fieldnames(qcl)))
    return;
end

stateID = double(sixgr.util.structGet(qcl, "state_id", NaN));
codepoint = double(sixgr.util.structGet(qcl, "codepoint", NaN));
activeStateID = double(sixgr.util.structGet(cfg, ...
    "phy.pdsch.activeTCIStateID", stateID));
if ~(localNonnegativeInteger(stateID) && ...
        localNonnegativeInteger(codepoint) && ...
        localNonnegativeInteger(activeStateID))
    error("sixgr:phy:grant:MalformedDLQCLTCIBinding", ...
        ["Installed DL QCL/TCI authority requires finite nonnegative integer " ...
         "state_id, codepoint, and activeTCIStateID values."]);
end
if activeStateID ~= stateID
    error("sixgr:phy:grant:InconsistentDLQCLTCIState", ...
        ["phy.pdsch.activeTCIStateID=%d differs from the installed " ...
         "phy.pdsch.qclTCI.state_id=%d."], activeStateID, stateID);
end

binding.Available = true;
binding.ActiveTCIStateID = stateID;
binding.TCICodepoint = codepoint;
binding.SpatialSourceResourceID = double(sixgr.util.structGet( ...
    qcl, "spatial_source_resource_id", NaN));
binding.SpatialSourceReferenceSignal = char(string(sixgr.util.structGet( ...
    qcl, "spatial_source_reference_signal", "")));
binding.ActivationAbsoluteSlot0 = double(sixgr.util.structGet( ...
    qcl, "activation_absolute_slot0", NaN));
binding.InitializationSource = char(string(sixgr.util.structGet( ...
    qcl, "initialization_source", "")));
binding.QCL = qcl;

digestPayload = rmfield(binding, "Digest");
binding.Digest = char(sixgr.util.sha256Hex(jsonencode(digestPayload)));
end

function tf = localNonnegativeInteger(value)
tf = isnumeric(value) && isscalar(value) && isreal(value) && ...
    isfinite(value) && value == fix(value) && value >= 0;
end
