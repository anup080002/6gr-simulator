function experimental=assertExperimentalCodingLayout(coding)
% Validate frozen experimental codepoint semantics, not ambient candidates.
name=string(sixgr.util.structGet(coding,'MCSTable',''));
experimental=startsWith(name,"experimental_");
if ~experimental, return; end
id='sixgr:research:FrozenTransportContextMismatch';
required={'ExperimentalMCSTable','ResearchTransportPolicy','TransportContextSHA256', ...
    'StandardNR','ResearchClass','MCSIndex','Modulation','TargetCodeRate'};
assert(all(isfield(coding,required)),id, ...
    'Frozen experimental coding requires complete table contents, UCI policy and classification.');
definition=sixgr.phy.research.resolveExperimentalMCSTable(name);
assert(~isempty(definition) && isequaln(coding.ExperimentalMCSTable,definition) && ...
    isequal(coding.StandardNR,false) && string(coding.ResearchClass)==definition.ResearchClass, ...
    id,'Frozen experimental table contents and research classification must remain valid.');
policy=coding.ResearchTransportPolicy;
assert(isstruct(policy) && isscalar(policy) && ...
    string(sixgr.util.structGet(policy,'meta.research_class',''))==definition.ResearchClass && ...
    string(sixgr.util.structGet(policy,'research_pusch_uci.resource_mapping',''))== ...
    "symbol_preserving_single_codeword_ulsch",id,'Frozen experimental UCI policy is invalid.');
context=struct('ExperimentalMCSTable',definition,'ResearchTransportPolicy',policy);
assert(isequal(string(coding.TransportContextSHA256),sixgr.util.sha256Hex(jsonencode(context))), ...
    id,'Experimental transport contents differ from their frozen identity.');
row=find(definition.Rows(:,1)==coding.MCSIndex);
assert(isscalar(row),id,'Frozen experimental MCS is absent from its table.');
profile=sixgr.link.resolveMCSProfile(name,coding.MCSIndex);
assert(profile.Valid && string(coding.Modulation)==string(profile.Modulation) && ...
    isequal(double(coding.TargetCodeRate),double(profile.TargetCodeRate)), ...
    id,'Frozen experimental modulation and code rate must match the selected codepoint.');
end
