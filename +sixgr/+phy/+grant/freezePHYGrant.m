function [W, source, meta] = localResolveDLLogicalPrecoder(cfg, grant, nLayers, nPorts, nElements)
source = "";
W = [];
pmi = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "AppliedPrecoderPMI", []), ...
    sixgr.util.structGet(grant, "PMI", []), ...
    sixgr.util.structGet(grant, "TPMI", []), ...
    sixgr.util.structGet(cfg, "phy.pdsch.PMI", []), ...
    sixgr.util.structGet(cfg, "phy.pdsch.pmi", []), NaN);
mode = localFirstNonempty( ...
    sixgr.util.structGet(grant, "AppliedPrecoderCodebookMode", ""), ...
    sixgr.util.structGet(grant, "PMICodebookMode", ""), ...
    sixgr.util.structGet(cfg, "phy.csi.pmiCodebookMode", ""), ...
    "type1_su_mimo");
meta = struct("PMI", double(pmi), "PMIType", "", ...
    "CodebookMode", string(mode), "BeamIndices", zeros(1, 0), ...
    "CSIRSPortBasisApplied", false, "CSIResourceIndex", NaN, ...
    "PMICodebookMatrixCSIPorts", [], ...
    "PMICodebookMatrixCSIPortsSHA256", "", ...
    "CSIRSPortToElementMatrix", [], ...
    "CSIRSPortToElementMatrixSHA256", "", ...
    "ComposedElementMatrix", [], ...
    "ComposedElementMatrixSHA256", "");
if ~isfinite(pmi)
    error("sixgr:phy:grant:MissingDLPMI", ...
        ["A scheduled multi-port DL grant without an explicit precoding matrix " ...
         "requires a finite PMI/TPMI. The frozen grant cannot substitute identity precoding."]);
end
try
    [candidates, info] = sixgr.phy.dl.pmiCodebookCandidates( ...
        cfg, nLayers, nPorts, "Mode", mode);
    if isempty(candidates)
        error("sixgr:phy:grant:EmptyDLPMICodebook", ...
            "No DL PMI candidates exist for %d port(s), %d layer(s), mode '%s'.", ...
            nPorts, nLayers, char(string(mode)));
    end
    pmi0 = round(double(pmi));
    if pmi0 ~= double(pmi) || pmi0 < 0 || pmi0 >= numel(candidates)
        error("sixgr:phy:grant:DLPMIOutOfRange", ...
            "Scheduled DL PMI=%g is invalid for mode '%s' with %d candidate(s).", ...
            double(pmi), char(string(mode)), numel(candidates));
    end
    idx = pmi0 + 1;
    Wcand = double(candidates(idx).W);
    if ~isequal(size(Wcand), [nPorts nLayers])
        error("sixgr:phy:grant:DLPMICodebookShapeMismatch", ...
            ["Scheduled DL PMI=%d resolved to a %dx%d matrix; the frozen grant " ...
             "requires %dx%d (logical ports by layers)."], ...
            pmi0, size(Wcand, 1), size(Wcand, 2), nPorts, nLayers);
    end
    Wcsi = localNormalizeScheduledDLCodebookMatrix(Wcand, ...
        localResolvePrecoderNormalizationConvention(cfg, grant, "bs", "PDSCH"));
    [W, basisMeta] = localComposeDLPMIWithCSIRSPortBasis( ...
        cfg, grant, Wcsi, nElements, nPorts, nLayers);
    if logical(basisMeta.Applied)
        source = "frozen_dl_pmi_codebook_composed_with_csirs_port_basis";
    else
        source = "frozen_dl_pmi_codebook_from_scheduled_grant";
    end
    meta.PMI = double(pmi0);
    meta.PMIType = string(sixgr.util.structGet(candidates(idx), "PMIType", ""));
    meta.CodebookMode = string(sixgr.util.structGet(candidates(idx), ...
        "CodebookMode", sixgr.util.structGet(info, "Mode", mode)));
    meta.BeamIndices = double(sixgr.util.structGet(candidates(idx), ...
        "BeamIndices", []));
    meta.CSIRSPortBasisApplied = logical(basisMeta.Applied);
    meta.CSIResourceIndex = double(basisMeta.CSIResourceIndex);
    meta.PMICodebookMatrixCSIPorts = double(Wcsi);
    meta.PMICodebookMatrixCSIPortsSHA256 = ...
        sixgr.phy.mimo.MatrixContract.digest(double(Wcsi));
    meta.CSIRSPortToElementMatrix = double(basisMeta.CSIRSPortToElementMatrix);
    meta.CSIRSPortToElementMatrixSHA256 = char(string( ...
        basisMeta.CSIRSPortToElementMatrixSHA256));
    meta.ComposedElementMatrix = double(basisMeta.ComposedElementMatrix);
    meta.ComposedElementMatrixSHA256 = char(string( ...
        basisMeta.ComposedElementMatrixSHA256));
catch ME
    if startsWith(string(ME.identifier), "sixgr:phy:grant:")
        rethrow(ME);
    end
    wrapped = MException("sixgr:phy:grant:DLPMIMaterializationFailed", ...
        "Failed to materialize scheduled DL PMI=%g: %s", double(pmi), ME.message);
    wrapped = addCause(wrapped, ME);
    throwAsCaller(wrapped);
end
end

function [WpdschPorts, meta] = localComposeDLPMIWithCSIRSPortBasis( ...
        cfg, grant, Wcsi, nElements, nPorts, nLayers)
% A Type-I PMI is defined in the measured CSI-RS antenna-port basis.  If
% CSI-RS ports were spatially filtered by B_CSIRS, data must use
% B_CSIRS*W_PMI in the physical element domain.  PDSCH may itself expose a
% logical port projection P, so freeze P\(B*W) only when the exact physical
% target lies in that configured subspace.
meta = struct("Applied", false, "CSIResourceIndex", NaN, ...
    "CSIRSPortToElementMatrix", [], ...
    "CSIRSPortToElementMatrixSHA256", "", ...
    "ComposedElementMatrix", [], "ComposedElementMatrixSHA256", "");
WpdschPorts = double(Wcsi);
precoders = sixgr.util.structGet(cfg, "phy.csirs.precoderMatrices", []);
if isempty(precoders)
    return;
end
if ~isnumeric(precoders) || any(~isfinite(real(precoders(:)))) || ...
        any(~isfinite(imag(precoders(:))))
    error("sixgr:phy:grant:InvalidCSIRSPortBasis", ...
        "phy.csirs.precoderMatrices must be a finite numeric tensor.");
end
nResources = size(precoders, 3);
cri = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "CRI", []), ...
    sixgr.util.structGet(grant, "AppliedCRI", []), ...
    sixgr.util.structGet(cfg, "phy.csi.selectedCRI", []), ...
    sixgr.util.structGet(cfg, "phy.beamManagement.selectedCRI", []), NaN);
if ~isfinite(cri)
    if nResources ~= 1
        error("sixgr:phy:grant:MissingDLCRIForCSIRSBasis", ...
            ['A scheduled PMI with %d CSI-RS resources requires the causal ' ...
             'zero-based CRI used to select its physical port basis.'], nResources);
    end
    cri = 0;
end
cri0 = round(double(cri));
if cri0 ~= double(cri) || cri0 < 0 || cri0 >= nResources
    error("sixgr:phy:grant:DLCRIOutOfRange", ...
        "Scheduled CRI=%g is outside the configured CSI-RS resource range [0,%d].", ...
        double(cri), nResources - 1);
end
B = complex(double(precoders(:, :, cri0 + 1)));
if ~isequal(size(B), [nElements nPorts])
    error("sixgr:phy:grant:CSIRSPortBasisShapeMismatch", ...
        ['CSI-RS resource CRI=%d has a %dx%d physical-element by CSI-port ' ...
         'basis; scheduled PDSCH requires %dx%d.'], ...
        cri0, size(B, 1), size(B, 2), nElements, nPorts);
end
gramResidual = norm(B' * B - eye(nPorts), "fro");
if gramResidual > 1e-10
    error("sixgr:phy:grant:CSIRSPortBasisNotSemiUnitary", ...
        "CSI-RS resource CRI=%d port basis is not semi-unitary (residual %.3g).", ...
        cri0, gramResidual);
end
targetElementMatrix = B * Wcsi;
arch = sixgr.rf.AntennaArrayFactory.resolvePortArchitecture(cfg, "bs", ...
    "Signal", "PDSCH", "NumElements", double(nElements), ...
    "NumPorts", double(nPorts), "MinimumPorts", double(nLayers));
P = complex(double(sixgr.util.structGet(arch, "PortToElementMatrix", [])));
if ~isequal(size(P), [nElements nPorts]) || ...
        any(~isfinite(real(P(:)))) || any(~isfinite(imag(P(:))))
    error("sixgr:phy:grant:InvalidPDSCHPortProjection", ...
        "PDSCH port-to-element projection must be a finite %dx%d matrix.", ...
        nElements, nPorts);
end
projectionGramResidual = norm(P' * P - eye(nPorts), "fro");
if projectionGramResidual > 1e-10
    error("sixgr:phy:grant:PDSCHPortProjectionNotSemiUnitary", ...
        "PDSCH port-to-element projection is not semi-unitary (residual %.3g).", ...
        projectionGramResidual);
end
WpdschPorts = P' * targetElementMatrix;
projectionResidual = norm(P * WpdschPorts - targetElementMatrix, "fro") ./ ...
    max(norm(targetElementMatrix, "fro"), eps);
if ~(isfinite(projectionResidual) && projectionResidual <= 1e-9)
    error("sixgr:phy:grant:CSIRSPMIPrecoderOutsidePDSCHSubspace", ...
        ['B_CSIRS*W_PMI for CRI=%d is outside the configured PDSCH port ' ...
         'subspace (relative residual %.3g).'], cri0, projectionResidual);
end
meta.Applied = true;
meta.CSIResourceIndex = double(cri0);
meta.CSIRSPortToElementMatrix = B;
meta.CSIRSPortToElementMatrixSHA256 = ...
    sixgr.phy.mimo.MatrixContract.digest(B);
meta.ComposedElementMatrix = targetElementMatrix;
meta.ComposedElementMatrixSHA256 = ...
    sixgr.phy.mimo.MatrixContract.digest(targetElementMatrix);
end

function W = localNormalizeScheduledDLCodebookMatrix(W, convention)
convention = lower(strtrim(string(convention)));
W = double(W);
if convention == "unit_frobenius"
    scale = norm(W, "fro");
    if ~(isscalar(scale) && isfinite(scale) && scale > 0)
        error("sixgr:phy:grant:DLPMICodebookNormalizationFailure", ...
            "Scheduled DL PMI resolved to a zero or non-finite precoding matrix.");
    end
    W = W ./ scale;
elseif ~any(convention == ["semi_unitary", "explicit_no_normalization"])
    error("sixgr:mimo:PrecoderNormalizationConventionUnsupported", ...
        "Unsupported frozen PDSCH precoder normalization convention '%s'.", ...
        char(convention));
end
end

