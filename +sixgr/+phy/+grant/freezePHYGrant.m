function localValidateULSRSCodebookAuthority(cfg, grant, nLayers, nPorts, tpmi)
if ~(isscalar(tpmi) && isfinite(tpmi) && tpmi >= 0 && tpmi == round(tpmi))
    error("sixgr:phy:grant:MissingULTPMI", ...
        "Codebook PUSCH requires a finite non-negative integer TPMI in the scheduled grant.");
end
strictMIMO = logical(sixgr.util.structGet(cfg, "mimo.strict", ...
    sixgr.util.structGet(cfg, "phy.mimo.strict", false)));
if ~strictMIMO
    return;
end
causalUsable = logical(sixgr.util.structGet(grant, "SRSCausalUsable", false));
srsValid = logical(sixgr.util.structGet(grant, "SRSValid", false));
measurementId = strtrim(string(sixgr.util.structGet(grant, ...
    "SRSCausalMeasurementId", "")));
measurementSlot = double(sixgr.util.structGet(grant, ...
    "LastSuccessfulSRSSlot", NaN));
ri = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "RI", []), ...
    sixgr.util.structGet(grant, "RIUsed", []), ...
    sixgr.util.structGet(grant, "NumLayers", []), NaN);
if ~causalUsable || ~srsValid || strlength(measurementId) == 0 || ...
        ~(isscalar(measurementSlot) && isfinite(measurementSlot))
    error("sixgr:mimo:MissingSRSState", ...
        "Strict codebook PUSCH grant requires a usable causal SRS measurement identity and slot.");
end
if ~(isscalar(ri) && isfinite(ri) && round(ri) == round(nLayers))
    error("sixgr:mimo:RankIdentityMismatch", ...
        "Causal SRS RI %g differs from scheduled PUSCH layers %d.", ri, nLayers);
end
if nPorts < nLayers
    error("sixgr:mimo:PortIdentityMismatch", ...
        "Scheduled PUSCH codebook ports %d are fewer than layers %d.", nPorts, nLayers);
end
end

function [Wphysical, nWaveformColumns, waveformDomain, elementDomainApplied, F, Wlogical] = ...
        localMaterializeElementDomainPrecoder(cfg, role, signal, nElements, nLogicalPorts, nLayers, Wlogical, Wraw, grant)
% Preserve the two distinct contracts: NR mapping uses logical ports, while
% an enabled hybrid RF/baseband architecture emits one waveform column per
% physical element. A frozen grant stores both matrices explicitly.
if isempty(Wlogical)
    Wlogical = [];
else
    Wlogical = localNormalizeDLMatrix(Wlogical, nLogicalPorts, nLayers);
end
Wphysical = Wlogical;
nWaveformColumns = nLogicalPorts;
waveformDomain = "logical_port";
elementDomainApplied = false;
F = [];

frozenRFChains = double(sixgr.util.structGet(grant, "NumRFChains", NaN));
if ~(isscalar(frozenRFChains) && isfinite(frozenRFChains) && frozenRFChains >= nLogicalPorts && ...
        frozenRFChains == round(frozenRFChains))
    frozenRFChains = NaN;
end
matrixAuthorityScope = "signal_then_role";
if localUsesMeasuredMUMIMOBaseArchitecture(grant, signal)
    % A signal-level PDSCH matrix is a selection owned by one earlier
    % grant.  It is not the immutable hybrid-array architecture used to
    % design a new measured-SRS MU group.  Bind strict measured-MU grants
    % to the YAML-owned role matrix, exactly as the MU designer does, and
    % then retain the existing residual/digest guards below.
    matrixAuthorityScope = "role_only";
end
arch = sixgr.rf.AntennaArrayFactory.resolvePortArchitecture(cfg, string(role), ...
    "Signal", string(signal), "NumElements", double(nElements), ...
    "NumPorts", double(nLogicalPorts), "NumRFChains", frozenRFChains, ...
    "MinimumPorts", double(nLayers), ...
    "MatrixAuthorityScope", matrixAuthorityScope);
if ~logical(sixgr.util.structGet(arch, "HybridBeamformingEnabled", false))
    if isempty(Wlogical)
        if isempty(Wraw)
            Wlogical = localRectIdentity(nLogicalPorts, nLayers, ...
                localResolvePrecoderNormalizationConvention(cfg, grant, role, signal));
        else
            Wlogical = localNormalizeDLMatrix(Wraw, nLogicalPorts, nLayers);
        end
    end
    Wphysical = Wlogical;
    return;
end

F = double(sixgr.util.structGet(arch, "HybridElementToPortMatrix", []));
if isempty(F) || ~ismatrix(F) || size(F, 1) ~= nElements || size(F, 2) ~= nLogicalPorts
    error("sixgr:phy:grant:HybridMatrixShapeMismatch", ...
        "Hybrid %s architecture matrix is %dx%d; expected %dx%d element-by-logical-port.", ...
        char(signal), size(F, 1), size(F, 2), nElements, nLogicalPorts);
end
frozenF = double(sixgr.util.structGet(grant, "HybridElementToPortMatrix", []));
if ~isempty(frozenF)
    if ~ismatrix(frozenF) || ~isequal(size(frozenF), [nElements nLogicalPorts]) || ...
            any(~isfinite(real(frozenF(:)))) || any(~isfinite(imag(frozenF(:))))
        error("sixgr:phy:grant:FrozenHybridArchitectureShapeMismatch", ...
            "Frozen %s hybrid architecture must be a finite %dx%d element-by-logical-port matrix.", ...
            char(signal), nElements, nLogicalPorts);
    end
    architectureResidual = norm(F - frozenF, "fro") / max(norm(frozenF, "fro"), eps);
    if architectureResidual > 1e-12
        configuredPolicy = lower(strtrim(string(sixgr.util.structGet(cfg, ...
            "mac.scheduler.muMimoHybridRFDesignPolicy", ...
            sixgr.util.structGet(cfg, "phy.mimo.muMimoHybridRFDesignPolicy", ...
            "fixed_configured_matrix")))));
        frozenPolicy = lower(strtrim(string(sixgr.util.structGet(grant, ...
            "MUMIMOHybridRFDesignPolicy", "fixed_configured_matrix"))));
        adaptivePolicy = "measured_srs_phase_only_subarray";
        if upper(string(signal)) ~= "PDSCH" || configuredPolicy ~= adaptivePolicy || ...
                frozenPolicy ~= configuredPolicy
            error("sixgr:phy:grant:FrozenHybridArchitectureMismatch", ...
                ['Frozen %s RF/baseband architecture differs from the architecture resolved with ' ...
                 'the frozen RF-chain count (relative residual %.3g).'], ...
                char(signal), architectureResidual);
        end
        localValidateAdaptiveHybridGrant(F, frozenF, grant);
    end
    F = frozenF;
end

rawPorts = localMatrixPortCount(Wraw, nLayers);
if isempty(Wlogical) && ~isempty(Wraw) && isfinite(rawPorts) && round(rawPorts) == nElements
    WrawPhysical = localNormalizeDLMatrix(Wraw, nElements, nLayers);
    Wlogical = pinv(F) * WrawPhysical;
elseif isempty(Wlogical) && ~isempty(Wraw)
    Wlogical = localNormalizeDLMatrix(Wraw, nLogicalPorts, nLayers);
end

if isempty(Wlogical)
    Wlogical = localRectIdentity(nLogicalPorts, nLayers, ...
        localResolvePrecoderNormalizationConvention(cfg, grant, role, signal));
end
Wphysical = F * Wlogical;
if isfinite(rawPorts) && round(rawPorts) == nElements
    WrawPhysical = localNormalizeDLMatrix(Wraw, nElements, nLayers);
    residual = norm(Wphysical - WrawPhysical, "fro") / max(norm(WrawPhysical, "fro"), eps);
    if residual > 1e-9
        error("sixgr:phy:grant:HybridPrecoderSubspaceMismatch", ...
            "The frozen %s %dx%d element-domain precoder is outside the configured %dx%d hybrid logical-port subspace (relative residual %.3g).", ...
            char(signal), size(WrawPhysical, 1), size(WrawPhysical, 2), size(F, 1), size(F, 2), residual);
    end
    Wphysical = WrawPhysical;
end
nWaveformColumns = size(Wphysical, 1);
waveformDomain = "element";
elementDomainApplied = true;
end

function tf = localUsesMeasuredMUMIMOBaseArchitecture(grant, signal)
tf = false;
if upper(strtrim(string(signal))) ~= "PDSCH"
    return;
end
contractVersion = strtrim(string(sixgr.util.structGet(grant, ...
    "MUMIMOSpatialDesignContractVersion", "")));
evidenceSource = lower(strtrim(string(sixgr.util.structGet(grant, ...
    "MUMIMOSpatialDesignEvidenceSource", ""))));
currentMeasuredMU = logical(sixgr.util.structGet( ...
    grant, "MUMIMOEnabled", false)) && ...
    double(sixgr.util.structGet(grant, "MUMIMOGroupSize", 0)) >= 2;
historicalMeasuredMU = logical(sixgr.util.structGet( ...
    grant, "IsRetransmission", false)) && ...
    double(sixgr.util.structGet(grant, "PriorMUMIMOGroupSize", 0)) >= 2;
tf = (currentMeasuredMU || historicalMeasuredMU) && ...
    startsWith(contractVersion, "MeasuredMUMIMOPairDesign/") && ...
    (contains(evidenceSource, "measured_srs") || ...
     contains(evidenceSource, "measured_csirs"));
end

function localValidateAdaptiveHybridGrant(baseF, frozenF, grant)
contractVersion = string(sixgr.util.structGet(grant, ...
    "MUMIMOSpatialDesignContractVersion", ""));
subspaceMode = lower(strtrim(string(sixgr.util.structGet(grant, ...
    "MUMIMOSpatialSignatureSubspaceMode", ""))));
designStatus = string(sixgr.util.structGet(grant, "MUMIMOSpatialDesignStatus", ""));
evidenceSource = string(sixgr.util.structGet(grant, ...
    "MUMIMOSpatialDesignEvidenceSource", ...
    sixgr.util.structGet(grant, "MUMIMOPairingEvidenceSource", "")));
if contractVersion ~= "MeasuredMUMIMOPairDesign/v13" || ...
        subspaceMode ~= "complete_detectable_subspace" || ...
        designStatus ~= "compatible_executable_measured_spatial_design" || ...
        evidenceSource ~= "causal_measured_srs_complete_peer_subspace_reciprocity_phase_only_hybrid_and_frozen_baseband"
    error("sixgr:phy:grant:FrozenHybridArchitectureAuthorityMissing", ...
        "Adaptive hybrid RF phases require a compatible v13 joint-per-victim " + ...
        "unit-total-power complete-peer-subspace measured-SRS design and its " + ...
        "exact causal reciprocity evidence source.");
end
baseSupport = abs(baseF) > 1e-14;
frozenSupport = abs(frozenF) > 1e-14;
magnitudeResidual = norm(abs(baseF) - abs(frozenF), "fro") ./ ...
    max(norm(abs(baseF), "fro"), eps);
if ~isequal(baseSupport, frozenSupport) || magnitudeResidual > 1e-12 || ...
        any(abs(sum(abs(frozenF).^2, 1) - sum(abs(baseF).^2, 1)) > 1e-12)
    error("sixgr:phy:grant:FrozenHybridArchitectureHardwareMismatch", ...
        "Adaptive hybrid RF matrix changed the configured subarray support, " + ...
        "constant-modulus magnitudes, or per-chain normalization (residual %.3g).", ...
        magnitudeResidual);
end
expectedBaseDigest = strtrim(string(sixgr.util.structGet(grant, ...
    "BaseHybridElementToPortMatrixSHA256", "")));
actualBaseDigest = string(sixgr.phy.mimo.MatrixContract.digest(baseF));
if strlength(expectedBaseDigest) ~= 64 || expectedBaseDigest ~= actualBaseDigest
    error("sixgr:phy:grant:FrozenHybridArchitectureBaseDigestMismatch", ...
        "Adaptive hybrid RF grant is not bound to the configured base architecture digest.");
end
expectedFrozenDigest = strtrim(string(sixgr.util.structGet(grant, ...
    "HybridElementToPortMatrixSHA256", "")));
actualFrozenDigest = string(sixgr.phy.mimo.MatrixContract.digest(frozenF));
if strlength(expectedFrozenDigest) ~= 64 || expectedFrozenDigest ~= actualFrozenDigest
    error("sixgr:phy:grant:FrozenHybridArchitectureDigestMismatch", ...
        "Adaptive hybrid RF grant matrix differs from its frozen matrix digest.");
end
end

function W = localNormalizeDLMatrix(Wraw, nPorts, nLayers)
if isempty(Wraw)
    W = localRectIdentity(nPorts, nLayers);
    return;
end
Wraw = double(Wraw);
if ndims(Wraw) > 2 && size(Wraw, 3) == 1
    Wraw = squeeze(Wraw);
end
if ~ismatrix(Wraw)
    error("sixgr:phy:grant:BadPrecodingMatrix", ...
        "PHYGrant DL PrecodingState.Matrix must be a 2-D matrix.");
end
if size(Wraw, 2) == nLayers
    W = Wraw;
elseif size(Wraw, 1) == nLayers
    W = Wraw.';
elseif size(Wraw, 2) > nLayers && size(Wraw, 1) >= nLayers
    W = Wraw(:, 1:nLayers);
else
    error("sixgr:phy:grant:BadPrecodingMatrix", ...
        "DL precoding matrix must be Nports-by-Nlayers or transpose. Got %dx%d for %d layer(s).", ...
        size(Wraw, 1), size(Wraw, 2), nLayers);
end
end

