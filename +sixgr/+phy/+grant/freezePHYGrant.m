function phyGrant = freezePHYGrant(cfg, direction, grant, varargin)
%FREEZEPHYGRANT Build the immutable PHY grant contract used by TX/RX/HARQ.
% Keep this file ASCII-only.

ip = inputParser;
ip.addParameter("SNR_dB", NaN, @(x) isempty(x) || (isnumeric(x) && isscalar(x)));
ip.addParameter("Frame", NaN, @(x) isempty(x) || (isnumeric(x) && isscalar(x)));
ip.addParameter("Slot", NaN, @(x) isempty(x) || (isnumeric(x) && isscalar(x)));
ip.addParameter("HARQContext", struct(), @(x) isempty(x) || isstruct(x));
ip.parse(varargin{:});
opt = ip.Results;

if nargin < 1 || ~isstruct(cfg)
    cfg = struct();
end
if nargin < 2 || strlength(string(direction)) == 0
    direction = sixgr.util.structGet(grant, "Direction", "DL");
end
if nargin < 3 || ~isstruct(grant)
    grant = struct();
end
direction = upper(string(direction));
if ~(direction == "DL" || direction == "UL")
    error("sixgr:phy:grant:BadDirection", ...
        "PHYGrant direction must be DL or UL. Got '%s'.", char(direction));
end

% Check before reuse as well as before construction: a frozen coding layout
% does not authorize reuse of the previous attempt's slot/symbol clock.
sixgr.phy.grant.assertGrantTimingIdentity(grant,direction);
existing = sixgr.util.structGet(grant, "PHYGrant", struct());
if localCanReuseFrozenPHYGrant(existing, cfg, direction, grant, opt)
    sixgr.phy.grant.assertPHYGrantDimensions(existing, "reuse_existing_phygrant");
    phyGrant = existing;
    return;
end

isUL = direction == "UL";
root = localChannelRoot(isUL);
runtimeRoot = localRuntimeDirectionRoot(isUL);
spatialContract = sixgr.phy.grant.resolveGrantSpatialContract(grant, ...
    "Direction", direction, ...
    "TBContext", sixgr.util.structGet(grant, "HARQTBContext", struct()), ...
    "RequireTBContextMatch", sixgr.phy.grant.isExplicitHARQRetransmission( ...
        grant, existing, opt.HARQContext));
frame = localFirstFiniteScalar(opt.Frame, sixgr.util.structGet(grant, "Frame", []), NaN);
slot = localFirstFiniteScalar(opt.Slot, sixgr.util.structGet(grant, "Slot", []), frame);
rnti = localFirstFiniteScalar(sixgr.util.structGet(grant, "RNTI", []), ...
    sixgr.util.structGet(cfg, root + ".RNTI", []), NaN);
ueIndex = localFirstFiniteScalar(sixgr.util.structGet(grant, "UEIndex", []), ...
    sixgr.util.structGet(grant, "UEID", []), ...
    sixgr.util.structGet(cfg, "lls6g.userContext.UEIndex", []), NaN);
servingCell = localFirstFiniteScalar(sixgr.util.structGet(grant, "ServingCell", []), ...
    sixgr.util.structGet(grant, "BaseStationID", []), ...
    sixgr.util.structGet(cfg, "lls6g.userContext.RuntimeServingCell", []), ...
    sixgr.util.structGet(cfg, "scenario.bs.cell_id", []), NaN);

numLayers = double(spatialContract.NumLayers);
numCodewords = localPositiveInteger(localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "NumCodewords", []), ...
    sixgr.util.structGet(grant, "CodewordCount", []), ...
    1 + double(numLayers > 4)), 1);
[dmrsPortSet, dmrsPortSetSource] = ...
    sixgr.phy.grant.resolveScheduledDMRSPortSet( ...
    cfg, direction, numLayers, grant);
[ptrsEnabled, ptrsPortSet, ptrsPortSetSource] = ...
    sixgr.phy.grant.resolveScheduledPTRSPortSet( ...
    cfg, direction, dmrsPortSet, grant);

prbSet = localResolvePRBSet(cfg, grant, root);
symbolAllocation = localResolveSymbolAllocation(cfg, grant, root);
[frequencyHoppingMode, frequencyHoppingToolboxMode, secondHopStartPRB] = ...
    localResolvePUSCHFrequencyHopping(cfg, grant, isUL);
modulation = char(string(localFirstNonempty( ...
    sixgr.util.structGet(grant, "Modulation", ""), ...
    sixgr.util.structGet(cfg, runtimeRoot + ".Modulation", ""), ...
    sixgr.util.structGet(cfg, root + ".modulation", "QPSK"))));
targetCodeRate = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "TargetCodeRate", []), ...
    sixgr.util.structGet(cfg, runtimeRoot + ".TargetCodeRate", []), ...
    sixgr.util.structGet(cfg, root + ".codeRate", []), NaN);
xOverhead = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "XOverhead", []), ...
    sixgr.util.structGet(cfg, root + ".xOverhead", []), 0);
nrePerPRB = localFirstFiniteScalar(sixgr.util.structGet(grant, "NREPerPRB", []), NaN);
tbsBits = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "TBSBits", []), ...
    sixgr.util.structGet(grant, "TransportBlockSize", []), ...
    sixgr.util.structGet(grant, "TBSize_bits", []), NaN);
tbsBytes = localFirstFiniteScalar(sixgr.util.structGet(grant, "TBSBytes", []), floor(max(tbsBits, 0) / 8));

[ant, prec] = localResolveAntennaAndPrecoding(cfg, grant, direction, numLayers, numCodewords);

resourceAllocation = struct( ...
    "PRBSet", double(prbSet(:).'), ...
    "PRBStart", localFirstFiniteScalar(min(double(prbSet(:))), sixgr.util.structGet(grant, "PRBStart", []), NaN), ...
    "PRBCount", double(numel(prbSet)), ...
    "SymbolAllocation", double(symbolAllocation(:).'), ...
    "SymbolStart", double(symbolAllocation(1)), ...
    "NumSymbols", double(symbolAllocation(2)), ...
    "FrequencyHoppingMode", char(frequencyHoppingMode), ...
    "FrequencyHoppingToolboxMode", char(frequencyHoppingToolboxMode), ...
    "FrequencyHoppingEnabled", logical(frequencyHoppingMode ~= "none"), ...
    "SecondHopStartPRB", double(secondHopStartPRB));

codingLayout = struct( ...
    "Modulation", char(modulation), ...
    "MCSIndex", localFirstFiniteScalar(sixgr.util.structGet(grant, "MCSIndex", []), ...
        sixgr.util.structGet(grant, "MCS", []), ...
        sixgr.util.structGet(cfg, runtimeRoot + ".MCSIndex", []), ...
        sixgr.util.structGet(cfg, root + ".mcsIndex", []), NaN), ...
    "MCSTable", char(string(localFirstNonempty(sixgr.util.structGet(grant, "MCSTable", ""), ...
        sixgr.util.structGet(cfg, runtimeRoot + ".MCSTable", ""), ...
        sixgr.util.structGet(cfg, root + ".mcsTable", "")))), ...
    "CQITable", char(string(localFirstNonempty(sixgr.util.structGet(grant, "CQITable", ""), ...
        sixgr.util.structGet(cfg, "link_adaptation.cqiTable", "")))), ...
    "TargetCodeRate", double(targetCodeRate), ...
    "XOverhead", double(xOverhead), ...
    "NREPerPRB", double(nrePerPRB), ...
    "TBSInputModulation", char(modulation), ...
    "TBSInputNumLayers", double(numLayers), ...
    "TBSInputNPRB", double(numel(prbSet)), ...
    "TBSInputNREPerPRB", double(nrePerPRB), ...
    "TBSInputTargetCodeRate", double(targetCodeRate), ...
    "TBSInputXOverhead", double(xOverhead), ...
    "TBSInputSource", char(string(sixgr.util.structGet(grant, ...
        "TBSInputSource", sixgr.util.structGet(grant, ...
        "ResourceAccountingSource", "transmitter_grant_resource_accounting")))), ...
    "TBSBits", double(tbsBits), ...
    "TBSBytes", double(tbsBytes), ...
    "NumLayers", double(numLayers), ...
    "NumCodewords", double(numCodewords), ...
    "DMRSPortSet", double(dmrsPortSet(:).'), ...
    "DMRSPortSetSource", char(string(dmrsPortSetSource)), ...
    "PTRSEnabled", logical(ptrsEnabled), ...
    "PTRSPortSet", double(ptrsPortSet(:).'), ...
    "PTRSPortSetSource", char(string(ptrsPortSetSource)));

noiseContext = struct( ...
    "SNR_dB", double(localFirstFiniteScalar(opt.SNR_dB, ...
        sixgr.util.structGet(cfg, "channel.snr_dB", []), NaN)), ...
    "NoiseVariance", localFirstFiniteScalar(sixgr.util.structGet(grant, "NoiseVariance", []), NaN), ...
    "NoiseSource", char(string(sixgr.util.structGet(grant, "NoiseSource", ""))));

channelStateKey = struct( ...
    "Direction", char(direction), ...
    "Frame", double(frame), ...
    "Slot", double(slot), ...
    "RNTI", double(rnti), ...
    "UEIndex", double(ueIndex), ...
    "ServingCell", double(servingCell), ...
    "ChannelModel", char(string(sixgr.util.structGet(cfg, "channel.model", "AWGN"))), ...
    "FadingProfile", char(localResolveFadingProfile(cfg)));

harqContext = opt.HARQContext;
harqFromGrant = sixgr.util.structGet(grant, "HARQ", struct());
harqProcessKey = struct( ...
    "Direction", char(direction), ...
    "RNTI", double(rnti), ...
    "HARQProcess", localFirstFiniteScalar( ...
        sixgr.util.structGet(harqContext, "HARQProcess", []), ...
        sixgr.util.structGet(harqContext, "HarqID", []), ...
        sixgr.util.structGet(harqFromGrant, "HARQProcess", []), ...
        sixgr.util.structGet(harqFromGrant, "HarqID", []), NaN), ...
    "RV", localFirstFiniteScalar( ...
        sixgr.util.structGet(harqContext, "RV", []), ...
        sixgr.util.structGet(harqFromGrant, "RV", []), ...
        sixgr.util.structGet(grant, "RV", []), NaN), ...
    "NDI", logical(localFirstFiniteScalar( ...
        sixgr.util.structGet(harqContext, "NDI", []), ...
        sixgr.util.structGet(harqFromGrant, "NDI", []), 1)), ...
    "IsRetransmission", sixgr.phy.grant.isExplicitHARQRetransmission( ...
        grant, existing, harqContext));

grantContextId = char(string(sixgr.util.structGet(grant, "GrantContextId", "")));
if strlength(string(grantContextId)) == 0
    grantContextId = localComposeContextId(direction, servingCell, ueIndex, rnti, frame, slot);
end
runtimeAuthorityDigest = localRuntimeAuthorityDigest(cfg);
configurationAuthority = struct( ...
    "ContractVersion", "sixgr_frozen_configuration_authority/v1", ...
    "RuntimeOperatingAuthoritySHA256", char(runtimeAuthorityDigest), ...
    "SourceConfigSHA256", char(string(sixgr.util.structGet(cfg, "meta.configHash", ""))), ...
    "Source", char(localRuntimeAuthoritySource(cfg)));

phyGrant = struct( ...
    "ContractVersion", "PHYGrant/v1", ...
    "IsFrozen", true, ...
    "Immutable", true, ...
    "MutationPolicy", "copy_only_recompute_forbidden_after_schedule", ...
    "Direction", char(direction), ...
    "GrantContextId", char(grantContextId), ...
    "PHYGrantId", char(grantContextId), ...
    "AntennaArchitecture", ant, ...
    "ResourceAllocation", resourceAllocation, ...
    "CodingLayout", codingLayout, ...
    "PrecodingState", prec, ...
    "NoiseContext", noiseContext, ...
    "ChannelStateKey", channelStateKey, ...
    "HARQProcessKey", harqProcessKey, ...
    "ConfigurationAuthority", configurationAuthority, ...
    "LegacyGrantSnapshot", grant);

phyGrant.DimensionContract = sixgr.phy.grant.assertPHYGrantDimensions( ...
    phyGrant, "freeze_phygrant");
end

function root = localChannelRoot(isUL)
if isUL
    root = "phy.pusch";
else
    root = "phy.pdsch";
end
end

function root = localRuntimeDirectionRoot(isUL)
if isUL
    root = "runtime.phy.ul";
else
    root = "runtime.phy.dl";
end
end

function tf = localIsFrozenPHYGrant(value)
tf = isstruct(value) && ~isempty(fieldnames(value)) && ...
    logical(sixgr.util.structGet(value, "IsFrozen", false)) && ...
    isfield(value, "AntennaArchitecture") && ...
    isfield(value, "ResourceAllocation") && ...
    isfield(value, "CodingLayout") && ...
    isfield(value, "PrecodingState");
end

function tf = localFrozenPHYGrantHasConsistentDimensions(value)
tf = false;
if ~localIsFrozenPHYGrant(value)
    return;
end
ant = sixgr.util.structGet(value, "AntennaArchitecture", struct());
coding = sixgr.util.structGet(value, "CodingLayout", struct());
prec = sixgr.util.structGet(value, "PrecodingState", struct());
numPorts = round(double(sixgr.util.structGet(ant, "NumWaveformColumns", NaN)));
numLogicalPorts = round(double(sixgr.util.structGet(ant, "NumLogicalPorts", NaN)));
numLayers = round(double(sixgr.util.structGet(coding, "NumLayers", ...
    sixgr.util.structGet(ant, "NumLayers", NaN))));
W = sixgr.util.structGet(prec, "MatrixPorts", sixgr.util.structGet(prec, "Matrix", []));
if isempty(W) || ~isnumeric(W)
    return;
end
if ndims(W) > 2 && size(W, 3) == 1
    W = squeeze(W);
end
if ~ismatrix(W)
    return;
end
Wlogical = sixgr.util.structGet(prec, "MatrixLogicalPorts", []);
logicalOK = true;
if logical(sixgr.util.structGet(prec, "HybridElementDomainApplied", false))
    logicalOK = isnumeric(Wlogical) && ismatrix(Wlogical) && ...
        size(Wlogical, 1) == numLogicalPorts && size(Wlogical, 2) == numLayers;
end
tf = isfinite(numPorts) && isfinite(numLogicalPorts) && isfinite(numLayers) && ...
    numLogicalPorts >= numLayers && numPorts >= numLogicalPorts && ...
    size(W, 1) == numPorts && size(W, 2) == numLayers && logicalOK;
end

function tf = localCanReuseFrozenPHYGrant(existing, cfg, direction, grant, opt)
tf = false;
if ~(localIsFrozenPHYGrant(existing) && localFrozenPHYGrantHasConsistentDimensions(existing))
    return;
end
if upper(string(sixgr.util.structGet(existing, "Direction", ""))) ~= upper(string(direction))
    return;
end
% Rebinding a legal new occasion still requires a new attempt snapshot.
% Identical TBS/precoding/resources alone cannot reuse the old clock.
if ~isequaln(sixgr.util.structGet(existing,'LegacyGrantSnapshot.TimingDecision',struct()), ...
        sixgr.util.structGet(grant,'TimingDecision',struct()))
    return;
end
frozenAuthorityDigest = string(sixgr.util.structGet(existing, ...
    "ConfigurationAuthority.RuntimeOperatingAuthoritySHA256", ""));
runtimeAuthorityDigest = localRuntimeAuthorityDigest(cfg);
if strlength(frozenAuthorityDigest) > 0 && strlength(runtimeAuthorityDigest) > 0 && ...
        frozenAuthorityDigest ~= runtimeAuthorityDigest
    error("sixgr:phy:grant:FrozenConfigurationAuthorityMismatch", ...
        ['Frozen %s grant configuration authority %s differs from the current ' ...
        'runtime operating authority %s; grant regeneration during replay is forbidden.'], ...
        char(direction), char(frozenAuthorityDigest), char(runtimeAuthorityDigest));
end

harqContext = sixgr.util.structGet(opt, "HARQContext", struct());
harqFromGrant = sixgr.util.structGet(grant, "HARQ", struct());
requestedIsRetx = sixgr.phy.grant.isExplicitHARQRetransmission( ...
    grant, existing, harqContext);
existingIsRetx = logical(sixgr.util.structGet(existing, "HARQProcessKey.IsRetransmission", false));
if requestedIsRetx ~= existingIsRetx
    return;
end

requestedRV = localFirstFiniteScalar( ...
    sixgr.util.structGet(harqContext, "RV", []), ...
    sixgr.util.structGet(harqFromGrant, "RV", []), ...
    sixgr.util.structGet(grant, "RV", []), NaN);
existingRV = localFirstFiniteScalar(sixgr.util.structGet(existing, "HARQProcessKey.RV", []), NaN);
if ~localScalarMatches(requestedRV, existingRV, 0)
    return;
end

requestedNDI = localFirstFiniteScalar( ...
    sixgr.util.structGet(harqContext, "NDI", []), ...
    sixgr.util.structGet(harqFromGrant, "NDI", []), NaN);
existingNDI = localFirstFiniteScalar(sixgr.util.structGet(existing, "HARQProcessKey.NDI", []), NaN);
if ~localScalarMatches(requestedNDI, existingNDI, 0)
    return;
end

requestedHarqProc = localFirstFiniteScalar( ...
    sixgr.util.structGet(harqContext, "HARQProcess", []), ...
    sixgr.util.structGet(harqContext, "HarqID", []), ...
    sixgr.util.structGet(harqFromGrant, "HARQProcess", []), ...
    sixgr.util.structGet(harqFromGrant, "HarqID", []), NaN);
existingHarqProc = localFirstFiniteScalar(sixgr.util.structGet(existing, "HARQProcessKey.HARQProcess", []), NaN);
if ~localScalarMatches(requestedHarqProc, existingHarqProc, 0)
    return;
end

isUL = direction == "UL";
root = localChannelRoot(isUL);
requestedPRBSet = localResolvePRBSet(cfg, grant, root);
existingPRBSet = double(sixgr.util.structGet(existing, "ResourceAllocation.PRBSet", []));
if ~localNumericVectorMatches(requestedPRBSet, existingPRBSet)
    return;
end

requestedSymbolAllocation = localResolveSymbolAllocation(cfg, grant, root);
existingSymbolAllocation = double(sixgr.util.structGet(existing, "ResourceAllocation.SymbolAllocation", []));
if ~localNumericVectorMatches(requestedSymbolAllocation, existingSymbolAllocation)
    return;
end

[requestedHoppingMode, ~, requestedSecondHop] = ...
    localResolvePUSCHFrequencyHopping(cfg, grant, isUL);
existingHoppingMode = lower(strtrim(string(sixgr.util.structGet(existing, ...
    "ResourceAllocation.FrequencyHoppingMode", "none"))));
if requestedHoppingMode ~= existingHoppingMode
    return;
end
if requestedHoppingMode ~= "none"
    existingSecondHop = double(sixgr.util.structGet(existing, ...
        "ResourceAllocation.SecondHopStartPRB", NaN));
    if ~localScalarMatches(requestedSecondHop, existingSecondHop, 0)
        return;
    end
end

requestedNumLayers = localPositiveInteger(localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "NumLayers", []), ...
    sixgr.util.structGet(grant, "Layers", []), ...
    sixgr.util.structGet(cfg, root + ".numLayers", []), ...
    sixgr.util.structGet(cfg, root + ".nLayers", []), 1), 1);
existingNumLayers = localFirstFiniteScalar(sixgr.util.structGet(existing, "CodingLayout.NumLayers", []), NaN);
if ~localScalarMatches(requestedNumLayers, existingNumLayers, 0)
    return;
end

requestedModulation = char(string(localFirstNonempty( ...
    sixgr.util.structGet(grant, "Modulation", ""), ...
    sixgr.util.structGet(cfg, root + ".modulation", "QPSK"))));
existingModulation = char(string(sixgr.util.structGet(existing, "CodingLayout.Modulation", "")));
if ~localTextMatches(requestedModulation, existingModulation)
    return;
end

requestedTargetCodeRate = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "TargetCodeRate", []), ...
    sixgr.util.structGet(cfg, root + ".codeRate", []), NaN);
existingTargetCodeRate = localFirstFiniteScalar(sixgr.util.structGet(existing, "CodingLayout.TargetCodeRate", []), NaN);
if ~localScalarMatches(requestedTargetCodeRate, existingTargetCodeRate, 1e-12)
    return;
end

requestedTBSBits = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "TBSBits", []), ...
    sixgr.util.structGet(grant, "TransportBlockSize", []), ...
    sixgr.util.structGet(grant, "TBSize_bits", []), NaN);
existingTBSBits = localFirstFiniteScalar(sixgr.util.structGet(existing, "CodingLayout.TBSBits", []), NaN);
if ~localScalarMatches(requestedTBSBits, existingTBSBits, 0)
    return;
end

requestedXOverhead = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "XOverhead", []), ...
    sixgr.util.structGet(cfg, root + ".xOverhead", []), 0);
existingXOverhead = localFirstFiniteScalar(sixgr.util.structGet(existing, "CodingLayout.XOverhead", []), NaN);
if ~localScalarMatches(requestedXOverhead, existingXOverhead, 1e-12)
    return;
end

requestedNREPerPRB = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "TBSInputNREPerPRB", []), ...
    sixgr.util.structGet(grant, "NREPerPRB", []), NaN);
existingNREPerPRB = localFirstFiniteScalar( ...
    sixgr.util.structGet(existing, "CodingLayout.TBSInputNREPerPRB", []), ...
    sixgr.util.structGet(existing, "CodingLayout.NREPerPRB", []), NaN);
if ~localScalarMatches(requestedNREPerPRB, existingNREPerPRB, 0)
    return;
end

tf = true;
end

function digest = localRuntimeAuthorityDigest(cfg)
digest = string(sixgr.util.structGet(cfg, ...
    "runtime.OperatingAuthoritySHA256", ""));
if strlength(strtrim(digest)) == 0
    digest = string(sixgr.util.structGet(cfg, "meta.configHash", ""));
end
digest = strtrim(digest);
end

function source = localRuntimeAuthoritySource(cfg)
if strlength(string(sixgr.util.structGet(cfg, ...
        "runtime.OperatingAuthoritySHA256", ""))) > 0
    source = "runtime_operating_authority";
elseif strlength(string(sixgr.util.structGet(cfg, "meta.configHash", ""))) > 0
    source = "resolved_scenario_config_hash";
else
    source = "unavailable_legacy_config";
end
end

function tf = localScalarMatches(requested, actual, tol)
if nargin < 3
    tol = 0;
end
tf = true;
if ~(isscalar(requested) && isfinite(double(requested)))
    return;
end
tf = isscalar(actual) && isfinite(double(actual)) && abs(double(requested) - double(actual)) <= tol;
end

function tf = localNumericVectorMatches(requested, actual)
requested = double(requested(:).');
actual = double(actual(:).');
requested = requested(isfinite(requested));
actual = actual(isfinite(actual));
if isempty(requested)
    tf = true;
    return;
end
tf = numel(requested) == numel(actual) && all(abs(requested - actual) <= 1e-9);
end

function tf = localTextMatches(requested, actual)
requested = upper(strtrim(string(requested)));
actual = upper(strtrim(string(actual)));
if strlength(requested) < 1
    tf = true;
    return;
end
tf = strlength(actual) >= 1 && requested == actual;
end

function prbSet = localResolvePRBSet(cfg, grant, root)
prbSet = sixgr.util.structGet(grant, "PRBSet", []);
if isempty(prbSet)
    prbStart = localFirstFiniteScalar(sixgr.util.structGet(grant, "PRBStart", []), NaN);
    prbCount = localFirstFiniteScalar( ...
        sixgr.util.structGet(grant, "AllocatedPRBCount", []), ...
        sixgr.util.structGet(grant, "PRBCount", []), ...
        sixgr.util.structGet(grant, "PRBs", []), NaN);
    if isfinite(prbStart) && isfinite(prbCount) && prbCount >= 1
        prbSet = round(prbStart):(round(prbStart) + round(prbCount) - 1);
    end
end
if isempty(prbSet)
    prbSet = sixgr.util.structGet(cfg, root + ".prbSet", []);
end
if isempty(prbSet)
    error("sixgr:phy:grant:MissingPRBSet", ...
        "PHYGrant requires an explicit PRBSet (or PRBStart plus PRBCount) " + ...
        "from the scheduled grant or resolved channel configuration.");
end
prbSet = localExpandPRBSet(prbSet);
if isempty(prbSet)
    error("sixgr:phy:grant:EmptyPRBSet", "PHYGrant requires a non-empty PRBSet.");
end
end

function prbSet = localExpandPRBSet(raw)
if ~(isnumeric(raw) && isreal(raw))
    error("sixgr:phy:grant:InvalidPRBSet", ...
        "PHYGrant PRBSet must be a real numeric vector.");
end
raw = double(raw(:).');
if isempty(raw)
    prbSet = [];
    return;
end
if any(~isfinite(raw)) || any(raw ~= fix(raw)) || any(raw < 0)
    error("sixgr:phy:grant:InvalidPRBSet", ...
        "PHYGrant PRBSet must contain finite nonnegative integers.");
end
if numel(raw) == 2 && raw(2) > raw(1)
    prbSet = round(raw(1)):round(raw(2));
else
    prbSet = unique(round(raw), "stable");
end
end

function symbolAllocation = localResolveSymbolAllocation(cfg, grant, root)
symbolAllocation = sixgr.util.structGet(grant, "SymbolAllocation", []);
if isempty(symbolAllocation)
    symbolAllocation = sixgr.util.structGet(cfg, root + ".symbolAllocation", []);
end
if isempty(symbolAllocation)
    error("sixgr:phy:grant:MissingSymbolAllocation", ...
        "PHYGrant requires an explicit SymbolAllocation from the scheduled " + ...
        "grant or resolved channel configuration.");
end
symbolAllocation = double(symbolAllocation(:).');
if numel(symbolAllocation) < 2 || ~all(isfinite(symbolAllocation(1:2)))
    error("sixgr:phy:grant:BadSymbolAllocation", ...
        "PHYGrant requires SymbolAllocation [start numSymbols].");
end
symbolAllocation = round(symbolAllocation(1:2));
if symbolAllocation(1) < 0 || symbolAllocation(2) < 1
    error("sixgr:phy:grant:BadSymbolAllocation", ...
        "Invalid SymbolAllocation [%d %d].", symbolAllocation(1), symbolAllocation(2));
end
end

function [mode, toolboxMode, secondHop] = localResolvePUSCHFrequencyHopping(cfg, grant, isUL)
mode = "none";
toolboxMode = "neither";
secondHop = NaN;
if ~isUL
    return;
end

raw = string(localFirstNonempty( ...
    sixgr.util.structGet(grant, "FrequencyHoppingMode", ""), ...
    sixgr.util.structGet(grant, "FrequencyHopping", ""), ...
    sixgr.util.structGet(grant, "PUSCHConfig.FrequencyHopping", ""), ...
    sixgr.util.structGet(cfg, "phy.pusch.frequencyHopping.mode", ""), ...
    sixgr.util.structGet(cfg, "phy.pusch.frequencyHopping", "none")));
token = lower(regexprep(strtrim(raw), "[-_ ]", ""));
switch token
    case {"", "none", "neither", "disabled", "off", "false"}
        mode = "none";
        toolboxMode = "neither";
    case {"intraslot", "intra"}
        mode = "intra_slot";
        toolboxMode = "intraSlot";
    case {"interslot", "inter"}
        mode = "inter_slot";
        toolboxMode = "interSlot";
    otherwise
        error("sixgr:phy:grant:InvalidPUSCHFrequencyHoppingMode", ...
            "Frozen UL grant has unsupported PUSCH frequency-hopping mode '%s'.", ...
            char(raw));
end

if mode == "none"
    return;
end
secondHop = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "SecondHopStartPRB", []), ...
    sixgr.util.structGet(grant, "PUSCHConfig.SecondHopStartPRB", []), ...
    sixgr.util.structGet(cfg, "phy.pusch.frequencyHopping.secondHopStartPRB", []), ...
    NaN);
if ~(isscalar(secondHop) && isfinite(secondHop) && secondHop == fix(secondHop) && secondHop >= 0)
    error("sixgr:phy:grant:MissingPUSCHSecondHopStartPRB", ...
        "Enabled PUSCH frequency hopping requires a finite nonnegative integer second-hop start PRB.");
end
secondHop = double(secondHop);
end

