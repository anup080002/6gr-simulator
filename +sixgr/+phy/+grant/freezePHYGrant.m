function value = localFirstFiniteScalar(varargin)
value = NaN;
for i = 1:nargin
    raw = varargin{i};
    if isempty(raw) || ~(isnumeric(raw) || islogical(raw))
        continue;
    end
    raw = double(raw(:));
    raw = raw(isfinite(raw));
    if ~isempty(raw)
        value = raw(1);
        return;
    end
end
end

function value = localPositiveInteger(value, fallback)
if ~(isscalar(value) && isfinite(double(value)) && double(value) >= 1)
    value = fallback;
end
value = max(1, round(double(value)));
end

function value = localFirstNonempty(varargin)
value = "";
for i = 1:nargin
    raw = string(varargin{i});
    raw = raw(~ismissing(raw));
    if ~isempty(raw) && strlength(strtrim(raw(1))) > 0
        value = raw(1);
        return;
    end
end
end

