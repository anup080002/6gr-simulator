function W = localRectIdentity(nPorts, nLayers, normalizationConvention)
if nargin < 3 || strlength(strtrim(string(normalizationConvention))) == 0
    normalizationConvention = "semi_unitary";
end
W = zeros(max(1, nPorts), max(1, nLayers));
activeStreams = min(size(W, 1), size(W, 2));
coefficient = 1 / sqrt(activeStreams);
if lower(strtrim(string(normalizationConvention))) == "semi_unitary"
    coefficient = 1;
end
for i = 1:activeStreams
    W(i, i) = coefficient;
end
end

function convention = localResolvePrecoderNormalizationConvention(cfg, grant, role, signal)
explicit = string(sixgr.util.structGet(grant, "PrecoderNormalizationConvention", ""));
if strlength(strtrim(explicit)) > 0
    convention = lower(strtrim(explicit));
elseif upper(strtrim(string(signal))) == "PUSCH" || lower(strtrim(string(role))) == "ue"
    convention = lower(strtrim(string(sixgr.util.structGet(cfg, ...
        "phy.pusch.precoding.normalizationConvention", ...
        sixgr.util.structGet(cfg, "pusch.precoder_normalization_convention", ...
        "semi_unitary")))));
else
    convention = lower(strtrim(string(sixgr.util.structGet(cfg, ...
        "phy.pdsch.precoding.normalizationConvention", ...
        sixgr.util.structGet(cfg, "pdsch.precoder_normalization_convention", ...
        "semi_unitary")))));
end
if ~any(convention == ["unit_frobenius","semi_unitary","explicit_no_normalization"])
    error("sixgr:mimo:PrecoderNormalizationConventionUnsupported", ...
        "Unsupported frozen %s precoder normalization convention '%s'.", ...
        char(string(signal)), convention);
end
end

function ports = localMatrixPortCount(W, nLayers)
ports = NaN;
if isempty(W) || ~isnumeric(W)
    return;
end
if ndims(W) > 2 && size(W, 3) == 1
    W = squeeze(W);
end
if ~ismatrix(W)
    return;
end
if size(W, 2) == nLayers
    ports = double(size(W, 1));
elseif size(W, 1) == nLayers
    ports = double(size(W, 2));
else
    ports = double(size(W, 1));
end
end

