function pairs=pairCSIRSTransmitterSymbols(prepared,observation)
% Actual post-RF transmitter EVM, not CSI channel-estimator residual/EVM.
% Compare on the frozen TX OFDM clock without fitting gain, phase or timing.
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && ...
    observation.isComplete() && observation.StartSample==prepared.TransmitStartSample && ...
    observation.EndSampleExclusive==prepared.TransmitStartSample+prepared.NumSamples && ...
    observation.SampleRateHz==prepared.SampleRateHz, ...
    'sixgr:refsig:CSITXEVMClock','Score the actual TX capture on its declared sample clock.');
reference=sixgr.phy.waveform.ofdmDemodulate(prepared.Carrier,prepared.TransmitSamples);
measured=sixgr.phy.waveform.ofdmDemodulate(prepared.Carrier,observation.readComplete());
mask=prepared.Tx.Grid~=0;
assert(isequal(size(reference),size(measured),size(mask)), ...
    'sixgr:refsig:CSITXEVMLayout','The physical TX grid, reference and capture must share all dimensions.');
pairs=struct([]);
for port=1:size(mask,3)
    indices=find(mask(:,:,port));
    if isempty(indices), continue; end
    r=reference(:,:,port); m=measured(:,:,port);
    entry=struct('SignalName',"CSI-RS",'PortIndex',port-1, ...
        'PortRole',"physical_TX_antenna_not_equalized_RX_stream", ...
        'ObservationID',"transmitted_CSIRS_"+string(observation.StartSample), ...
        'ObservationStartSample',observation.StartSample, ...
        'ObservationEndSampleExclusive',observation.EndSampleExclusive, ...
        'ObservationSampleRateHz',observation.SampleRateHz, ...
        'TransmitStartSample',prepared.TransmitStartSample, ...
        'MeasurementClockDomain',"physical_absolute_sample_clock_zero_based", ...
        'SampleIndex',double(indices(:)-1),'ReferenceReal',real(r(indices)), ...
        'ReferenceImag',imag(r(indices)),'MeasuredReal',real(m(indices)), ...
        'MeasuredImag',imag(m(indices)), ...
        'EVMDefinition',"reference_normalized_paired_symbol_evm", ...
        'AlignmentSource',"frozen_transmitter_OFDM_clock_no_gain_phase_or_timing_fit", ...
        'ReferenceSource',"actual_pre_TX_RF_waveform_on_declared_resource_clock", ...
        'MeasurementDomain',"transmitter_resource_elements", ...
        'ReceiverUsesScoringReference',false,'GainOrPhaseFitted',false);
    if isempty(pairs), pairs=entry; else, pairs(end+1)=entry; end %#ok<AGROW>
end
end
