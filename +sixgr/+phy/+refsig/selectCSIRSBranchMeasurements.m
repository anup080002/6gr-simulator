function selected=selectCSIRSBranchMeasurements(measurement)
% TS 38.215 5.1.2/5.1.4 selection-diversity reports from one CSI-RS resource.
% Independent RSRP and RSRQ selections must retain their respective branches.
% Do not form RSRQ using maxima taken from different receiver branches.
powerUnit=string(sixgr.util.structGet(measurement,'PowerUnit',"W_resource_grid"));
assert(isscalar(powerUnit) && any(powerUnit== ...
    ["W_resource_grid","relative_to_unit_occupied_RE_Es"]), ...
    'sixgr:phy:CSIRSMeasurementPowerUnit','Do not combine different power domains.');
suffix="_dBm";
if powerUnit=="relative_to_unit_occupied_RE_Es", suffix="_dB_re_UnitOccupiedRE_Es"; end
required=["Available","RSRPPerAntenna"+suffix,"RSSIPerAntenna"+suffix, ...
    "RSRQPerAntenna_dB","NumReceiveAntennas","NumRB","Source"];
assert(isstruct(measurement) && isscalar(measurement) && all(isfield(measurement,required)) && ...
    isscalar(measurement.Available) && measurement.Available, ...
    'sixgr:phy:CSIRSBranchMeasurementsUnavailable','Retain available physical per-branch measurements from one CSI-RS resource.');
n=double(measurement.NumReceiveAntennas); rb=double(measurement.NumRB);
validateattributes(n,{'numeric'},{'scalar','finite','integer','positive'});
validateattributes(rb,{'numeric'},{'scalar','finite','integer','positive'});
rsrp=double(measurement.("RSRPPerAntenna"+suffix)); rsrp=rsrp(:);
rssi=double(measurement.("RSSIPerAntenna"+suffix)); rssi=rssi(:);
rsrq=double(measurement.RSRQPerAntenna_dB(:));
assert(numel(rsrp)==n && numel(rssi)==n && numel(rsrq)==n && all(isfinite(rssi) | rssi==-Inf), ...
    'sixgr:phy:CSIRSBranchMeasurementShape','Do not discard missing branches or mix resource identities.');
valid=isfinite(rsrp) & isfinite(rsrq);
if ~all(valid)
    % A measured nonpositive signed power has no logarithm. It is not a
    % missing receive branch. Accept this case only with its actual signed
    % producer evidence; arbitrary missing RSRP/RSSI/RSRQ must still fail.
    power=double(sixgr.util.structGet(measurement,'SINR.DesiredPowerPerReceiveAntenna',[]));
    power=power(:);
    offset=30; if powerUnit=="relative_to_unit_occupied_RE_Es", offset=0; end
    assert(numel(power)==n && all(isfinite(power)) && any(valid) && ...
        all(power(~valid)<=0) && all(isnan(rsrp(~valid)) & isnan(rsrq(~valid))) && ...
        all(power(valid)>0) && all(abs(10*log10(power(valid))+offset-rsrp(valid))<1e-7), ...
        'sixgr:phy:CSIRSBranchMeasurementShape','Unavailable logarithms require matching signed received-power evidence.');
end
assert(all(abs(rsrq(valid)-(10*log10(rb)+rsrp(valid)-rssi(valid)))<1e-7), ...
    'sixgr:phy:CSIRSBranchRSRQClosure','Each branch must satisfy RSRQ = 10log10(N) + RSRP - RSSI over the same measurement RBs.');
source=string(measurement.Source);
assert(isscalar(source) && ~ismissing(source) && strlength(strtrim(source))>0, ...
    'sixgr:phy:CSIRSBranchMeasurementSource','Retain the measurement producer provenance.');
[power,powerBranch]=max(rsrp,[],'omitnan');
[quality,qualityBranch]=max(rsrq,[],'omitnan');
selected=struct('RSRP_dBm',NaN,'RSRPReceiveBranch1Based',powerBranch, ...
    'RSSI_dBm',NaN,'RSSIReceiveBranch1Based',powerBranch, ...
    'RSRQ_dB',quality,'RSRQReceiveBranch1Based',qualityBranch, ...
    'RSRQNumeratorRSRP_dBm',NaN, ...
    'RSRQDenominatorRSSI_dBm',NaN, ...
    'NumRB',rb,'MeasurementSource',source,'PowerUnit',powerUnit, ...
    'RSRPSelection',"maximum_individual_receive_branch", ...
    'RSRQSelection',"maximum_individual_receive_branch_same_branch_ratio", ...
    'RSSISelection',"same_branch_as_reported_rsrp_not_necessarily_rsrq_denominator");
selected.("RSRP"+suffix)=power;
selected.("RSSI"+suffix)=rssi(powerBranch);
selected.("RSRQNumeratorRSRP"+suffix)=rsrp(qualityBranch);
selected.("RSRQDenominatorRSSI"+suffix)=rssi(qualityBranch);
end
