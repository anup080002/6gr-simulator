function out=replaySSBPowerMeasurementOperator(samples,receipt)
%REPLAYSSBPOWERMEASUREMENTOPERATOR Post-receiver SSS power comparison only.
% Reuses the original noisy receiver's operation; no timing/CFO/channel
% estimation, RF/channel execution, power fitting or receiver feedback.
% The caller must separately bind these samples to their original runtime
% source and receive-column execution. This function is arithmetic, not an
% authorization to call arbitrary samples independent physical truth.
id='sixgr:refsig:SSBPowerOperator';
assert(isstruct(receipt)&&isscalar(receipt)&&receipt.Available&&receipt.FFTSupportAvailable&& ...
    any(string(receipt.ContractVersion)==["sixgr.ssb.original_preRF_power_measurement/v1","sixgr.ssb.original_preRF_power_measurement/v2"]),id, ...
    'An original supported pre-RF receipt is required.');
op=receipt.ReceiverOperator; d=op.OriginalDemodulation;
assert(string(d.EngineUsed)=="canonical_nrOFDMDemodulate"&& ...
    string(d.RuntimeMATLABRelease)==string(version('-release'))&& ...
    d.OFDMWindowingSamples==0&& ...
    d.LeftPaddingSamples==0,id,'Replay only the original qualified native unresampled operator.');
assert((isa(samples,'single')||isa(samples,'double'))&&ismatrix(samples)&& ...
    size(samples,1)==receipt.ObservationEndSampleExclusive-receipt.ObservationStartSample&& ...
    size(samples,2)==receipt.NumReceiveColumns&&all(isfinite(samples(:)))&& ...
    isequal(double(receipt.ReceiveColumnIndices0(:).'),0:size(samples,2)-1),id, ...
    'Retain original complete capture and column dimensions.');
for name=["SampleRate_Hz","SCS_SSB_kHz","Nfft","DemodulationSlot", ...
        "SSBDemodulationSampleCount","SSBDemodulationStartSampleZeroBased", ...
        "SymbolPhaseCompensationCarrierFrequencyHz","CFOCorrectionApplied_Hz", ...
        "CFOCorrectionSampleOrigin","SSBPlacementCorrectionAppliedHz"]
    value=op.(name);
    assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value),id, ...
        'Every original operator scalar must be finite and scalar.');
end
assert(op.SampleRate_Hz==op.Nfft*op.SCS_SSB_kHz*1000&& ...
    op.CFOCorrectionSampleOrigin==0&&islogical(op.CFOCorrectionApplied)&& ...
    isscalar(op.CFOCorrectionApplied)&&op.CFOCorrectionApplied&& ...
    op.Nfft==fix(op.Nfft)&&op.Nfft>=240&& ...
    op.DemodulationSlot>=0&&op.DemodulationSlot==fix(op.DemodulationSlot),id, ...
    'Preserve native FFT and original capture-origin frequency operation.');
offset=op.SSBDemodulationStartSampleZeroBased; count=op.SSBDemodulationSampleCount;
assert(offset>=0&&offset==fix(offset)&&count>0&&count==fix(count)&&offset+count<=size(samples,1),id, ...
    'No prefix padding, truncated crop or new alignment is admissible.');
columns=double(op.SSBSymbolColumnsOneBased(:).');
assert(numel(columns)==4&&columns(1)>=1&&isequal(columns,columns(1)+(0:3)),id, ...
    'The observed SSB has exactly four original consecutive symbols.');
carrier=nrCarrierConfig('NSizeGrid',20,'NStartGrid',0,'NCellID',0, ...
    'SubcarrierSpacing',op.SCS_SSB_kHz,'CyclicPrefix','normal','NFrame',0,'NSlot',op.DemodulationSlot);
probeAccounting=sixgr.phy.waveform.validateRecordedOFDMFFTAuthority(d,carrier, ...
    op.Nfft,op.SampleRate_Hz,double(d.CyclicPrefixFraction),numel(d.SymbolLengths), ...
    op.SymbolPhaseCompensationCarrierFrequencyHz, ...
    string(receipt.ContractVersion)=="sixgr.ssb.original_preRF_power_measurement/v1");
native=nrOFDMInfo(carrier,'Nfft',op.Nfft,'SampleRate',op.SampleRate_Hz,'Windowing',0);
pos=mod(mod(op.DemodulationSlot,carrier.SlotsPerSubframe)*14+(0:columns(end)-1), ...
    numel(native.SymbolLengths))+1;
cp=double(native.CyclicPrefixLengths(pos)); lengths=double(native.SymbolLengths(pos));
assert(isequal(cp,double(d.CyclicPrefixLengths(:).'))&& ...
    isequal(lengths,double(d.SymbolLengths(:).'))&&sum(lengths)==count&& ...
    isscalar(d.CyclicPrefixFraction)&&isfinite(d.CyclicPrefixFraction)&& ...
    d.CyclicPrefixFraction>=0&&d.CyclicPrefixFraction<=1,id,'Original CP/FFT geometry changed.');
starts=[0 cumsum(lengths(1:end-1))];
first=offset+starts(columns)+fix(cp(columns)*d.CyclicPrefixFraction);
assert(isequal([first(:) first(:)+op.Nfft],double(receipt.SelectedFFTIntervalsCaptureLocal0))&& ...
    isequal(double(receipt.SSSFFTIntervalCaptureLocal0(:).'),[first(3) first(3)+op.Nfft])&& ...
    isequal(double(receipt.SSSIndicesOneBased(:)),double(nrSSSIndices))&&receipt.SSSRECount==127,id, ...
    'Compare exactly the original observed SSS RE and FFT sample support.');
inputHash=sixgr.phy.waveform.WaveformHash.runtimeArray(samples);
n=(0:size(samples,1)-1).';
% These two multiplications preserve freqOffsetCorrect's original operation
% order and double-valued localFreqShift arithmetic, not a fused phase fit.
samples=samples.*exp(1i*2*pi*(op.SSBPlacementCorrectionAppliedHz/op.SampleRate_Hz)*n);
samples=samples.*exp(1i*2*pi*(-op.CFOCorrectionApplied_Hz/op.SampleRate_Hz)*n);
aligned=samples(offset+(1:count),:);
grid=nrOFDMDemodulate(carrier,aligned,'Nfft',op.Nfft,'SampleRate',op.SampleRate_Hz, ...
    'CarrierFrequency',op.SymbolPhaseCompensationCarrierFrequencyHz, ...
    'CyclicPrefixFraction',d.CyclicPrefixFraction);
assert(size(grid,1)==240&&size(grid,2)>=columns(end)&&size(grid,3)==size(samples,2),id, ...
    'Native replay must preserve original receive columns and occupied SSB grid.');
grid=grid(:,columns,:); support=double(nrSSSIndices);
reference=zeros(1,size(grid,3));
unit=string(receipt.WaveformAmplitudeUnit);
assert(isscalar(unit)&&any(unit==["sqrt_mW","normalized_complex_baseband"]),id,'Unknown applied power unit.');
for k=1:size(grid,3)
    branch=double(grid(:,:,k));
    reference(k)=mean(abs(branch(support)).^2);
end
powerUnit="relative_to_unit_occupied_RE_Es";
if unit=="sqrt_mW", reference=reference/(op.Nfft^2*1000); powerUnit="W"; end
assert(string(receipt.LinearPowerUnit)==powerUnit,id,'Original and reference power units differ.');
measured=double(receipt.OriginalMeasuredPowerPerReceiveColumn(:).');
raw=double(receipt.OriginalRawPowerPerReceiveColumn(:).');
noise=double(receipt.OriginalDisturbancePerReceiveColumn(:).');
assert(numel(measured)==numel(reference)&&numel(raw)==numel(reference)&&numel(noise)==numel(reference)&& ...
    all(isfinite([measured raw noise]))&&all([measured raw noise]>=0)&& ...
    receipt.OriginalEstimatorClipsNegativePowerAtZero,id,'Retain original practical power operands.');
% Conversion of all three original operands can introduce rounding; this is
% arithmetic closure, NOT a permitted receiver-power accuracy threshold.
tol=64*eps(max([realmin raw noise measured]));
assert(all(abs(measured-max(raw-noise,0))<=tol),id,'Original estimator operands are inconsistent.');
errorDB=nan(size(reference)); valid=reference>0&measured>0;
errorDB(valid)=10*log10(measured(valid)./reference(valid));
[bestMeasured,selected]=max(measured);
[bestReference,bestReferenceColumn]=max(reference);
reportedError=NaN; selectedError=NaN; selectedColumn=NaN;
if bestMeasured>0
    selectedColumn=selected-1; selectedError=errorDB(selected);
    if bestReference>0, reportedError=10*log10(bestMeasured/bestReference); end
end
out=struct('LinearPowerUnit',powerUnit,'ReferencePerReceiveColumn',reference, ...
    'OriginalMeasuredPerReceiveColumn',measured,'OriginalRawPerReceiveColumn',raw, ...
    'OriginalDisturbancePerReceiveColumn',noise,'LinearErrorPerReceiveColumn',measured-reference, ...
    'ErrorPerReceiveColumn_dB',errorDB,'MeasuredSelectedColumn0',selectedColumn, ...
    'ReferenceMaximumColumn0',bestReferenceColumn-1,'ReferenceMaximumPower',bestReference, ...
    'MeasuredSelectedColumnError_dB',selectedError,'ReportedError_dB',reportedError, ...
    'DesiredInputSHA256',inputHash,'AlignedSHA256',sixgr.phy.waveform.WaveformHash.numeric(aligned), ...
    'SSBGridSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(grid), ...
    'IsolatedCapabilityProbeDemodulations',probeAccounting.IsolatedProbeDemodulationsThisCall, ...
    'AdditionalOFDMDemodulationsScope',"original_operator_replay_only_excludes_isolated_capability_probes", ...
    'AdditionalOFDMDemodulations',1,'AdditionalTimingAcquisitions',0, ...
    'AdditionalFrequencyEstimations',0,'AdditionalChannelEstimations',0);
end
