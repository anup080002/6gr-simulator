function out=buildCSIRSPortReferenceInputs(prepared)
%BUILDCSIRSPORTREFERENCEINPUTS Mathematical pre-RF CSI-port decomposition.
% Use ORIGINAL prepared logical pilots, waveform-column precoders, native
% OFDM receipt and applied scalar. No encoding, power-context resolution,
% RF, channel, estimation or calibration probe is executed here. The extra
% native reference modulations are counted, not called physical emissions.
% Components are factorized: Samples * WaveformColumnWeights.' reconstructs
% one resource/port contribution in the ORIGINAL prepared column order.
% Samples already contains the ONE original amplitude scale. No installed
% antenna/stream ownership, nonlinear port attribution or RX power claim is
% established by this preparation-only helper.
% Initial subset: the configured resource-set producer retaining Resources.
% A legacy singleton without those original records is rejected, not rebuilt.

id='sixgr:refsig:InvalidCSIRSPortReferenceInputs';
mapID='sixgr:refsig:CSIRSPortReferenceMappingMismatch';
opID='sixgr:refsig:UnsupportedCSIRSPortReferenceOperator';
closureID='sixgr:refsig:CSIRSPortReferenceClosure';
localFields(prepared,{'ExecutionStage','Tx','TxInfo','Carrier','PowerContext', ...
    'TransmitSamples','SampleRateHz','NumSamples','NumPhysicalTransmitAntennas', ...
    'RFExecutionDeferred','PAExecutionDeferred','ChannelExecutionDeferred', ...
    'ReferenceIdentity','Timeline','RuntimeSlot'},id);
assert(string(prepared.ExecutionStage)=="csirs_waveform_prepared_not_received" && ...
    localFlag(prepared.RFExecutionDeferred,id) && ...
    localFlag(prepared.ChannelExecutionDeferred,id),id, ...
    'Only the original deferred independent CSI-RS preparation is supported.');
tx=prepared.Tx; power=prepared.PowerContext;
localFields(tx,{'Carrier','Grid','Waveform','OFDMInfo','CSIRSInfo', ...
    'CSIRSIndices','CSIRSSymbols','CSIRSRuntimeEvent','PowerContext'},id);
localFields(power,{'ContractVersion','AmplitudeScale','WaveformAmplitudeUnit', ...
    'PAApplied','PAEnabled','PAExecutionDeferred'},id);
assert(string(power.ContractVersion)=="sixgr.rf.PowerContext/v1" && ...
    ~localFlag(power.PAApplied,id) && ...
    (~localFlag(power.PAEnabled,id)||localFlag(power.PAExecutionDeferred,id)) && ...
    isequaln(power,tx.PowerContext) && ...
    isequal(prepared.PAExecutionDeferred,power.PAExecutionDeferred),id, ...
    'Original power authority must agree and nonlinear PA must not have executed.');
scale=power.AmplitudeScale;
assert(isnumeric(scale)&&isreal(scale)&&isscalar(scale)&&isfinite(scale)&&scale>=0,id, ...
    'Retain one original finite nonnegative amplitude scale.');
unit=string(power.WaveformAmplitudeUnit);
assert(isscalar(unit)&&any(unit==["sqrt_mW","normalized_complex_baseband"]),id, ...
    'Declare the original sample unit; normalized samples are not watts.');

carrier=prepared.Carrier; carrierRecord=localCarrier(carrier,id);
assert(isequaln(carrierRecord,localCarrier(tx.Carrier,id)),id, ...
    'Prepared and transmitted carrier identities differ.');
localFields(prepared.Timeline,{'AbsoluteSlotIndex0','AbsoluteSlotIndexOneBased', ...
    'CarrierSlotIndex0','CarrierFrameIndex0'},id);
assert(isequal(prepared.RuntimeSlot,prepared.Timeline.AbsoluteSlotIndexOneBased) && ...
    prepared.Timeline.AbsoluteSlotIndex0==prepared.RuntimeSlot-1 && ...
    carrier.NSlot==prepared.Timeline.CarrierSlotIndex0 && ...
    carrier.NFrame==prepared.Timeline.CarrierFrameIndex0 && ...
    prepared.Timeline.AbsoluteSlotIndex0== ...
        double(carrier.NFrame)*double(carrier.SlotsPerFrame)+double(carrier.NSlot),id, ...
    'Use the original prepared carrier clock, not a current configuration.');
grid=tx.Grid; waveform=tx.Waveform; transmitted=prepared.TransmitSamples;
localArray(grid,id); localArray(waveform,id); localArray(transmitted,id);
K=12*double(carrier.NSizeGrid); L=double(carrier.SymbolsPerSlot); plane=K*L;
columns=size(grid,3);
assert(ndims(grid)<=3 && size(grid,1)==K && size(grid,2)==L && ...
    ismatrix(waveform)&&ismatrix(transmitted)&& ...
    isequal(size(waveform),size(transmitted))&&size(waveform,2)==columns && ...
    strcmp(class(grid),class(waveform))&&strcmp(class(waveform),class(transmitted)) && ...
    prepared.NumSamples==size(waveform,1) && ...
    prepared.NumPhysicalTransmitAntennas==columns,id, ...
    'Original grid, waveform, sample precision and column dimensions must agree.');
ofdm=tx.OFDMInfo;
localFields(ofdm,{'EngineUsed','Nfft','SampleRate','Windowing','OFDMWindowingSamples', ...
    'CyclicPrefixLengths','SymbolLengths','OFDMSamplingResolution', ...
    'GridSize','WaveformSize','GridSHA256','WaveformSHA256'},opID);
resolution=ofdm.OFDMSamplingResolution;
localFields(resolution,{'Nfft','SampleRateHz','WindowingSamples','NSizeGrid', ...
    'CyclicPrefixLengths','SymbolLengths','CurrentSlotSamples'},opID);
assert(string(ofdm.EngineUsed)=="canonical_nrOFDMModulate" && ...
    isnumeric(ofdm.Nfft)&&isscalar(ofdm.Nfft)&&isfinite(ofdm.Nfft)&& ...
    ofdm.Nfft==fix(ofdm.Nfft)&&ofdm.Nfft>=K && ...
    ofdm.SampleRate==ofdm.Nfft*double(carrier.SubcarrierSpacing)*1000 && ...
    prepared.SampleRateHz==ofdm.SampleRate && ...
    ofdm.Windowing==0&&ofdm.OFDMWindowingSamples==0&&resolution.WindowingSamples==0 && ...
    resolution.Nfft==ofdm.Nfft&&resolution.SampleRateHz==ofdm.SampleRate && ...
    resolution.NSizeGrid==carrier.NSizeGrid && ...
    resolution.CurrentSlotSamples==size(waveform,1) && ...
    isequal(double(ofdm.CyclicPrefixLengths(:)),double(resolution.CyclicPrefixLengths(:))) && ...
    isequal(double(ofdm.SymbolLengths(:)),double(resolution.SymbolLengths(:))),opID, ...
    'Support only recorded native unresampled zero-windowing OFDM; never guess an operator.');
assert(isequal(double(ofdm.GridSize),double(size(grid))) && ...
    isequal(double(ofdm.WaveformSize),double(size(waveform))) && ...
    string(ofdm.GridSHA256)==localHash(grid) && ...
    string(ofdm.WaveformSHA256)==localHash(waveform),id, ...
    'Original native grid/waveform hashes or dimensions changed.');
localFields(prepared.TxInfo,{'PortGrid','OFDM','CSIRSRuntimeEvent'},id);
assert(isequaln(prepared.TxInfo.PortGrid,grid)&&isequaln(prepared.TxInfo.OFDM,ofdm) && ...
    isequaln(prepared.TxInfo.CSIRSRuntimeEvent,tx.CSIRSRuntimeEvent),id, ...
    'Do not mix independent original preparation operands.');
localFields(prepared.ReferenceIdentity,{'PhysicalGridDigest','AbsoluteSlotIndex0', ...
    'ResourceSetID','ResourceIDs'},id);
assert(string(prepared.ReferenceIdentity.PhysicalGridDigest)== ...
    sixgr.phy.mimo.MatrixContract.digest(grid) && ...
    prepared.ReferenceIdentity.AbsoluteSlotIndex0==prepared.Timeline.AbsoluteSlotIndex0,id, ...
    'Original preparation grid/clock identity changed.');
assert(isequal(transmitted,waveform.*cast(scale,'like',waveform)),id, ...
    'TransmitSamples must be the original aggregate scaled exactly once, before RF.');

localFields(tx.CSIRSInfo,{'Resources','NumResources','ResourceIDs','ResourceSetID'},mapID);
resources=tx.CSIRSInfo.Resources; event=tx.CSIRSRuntimeEvent;
localFields(event,{'ResourceEvents','Scheduled','Transmitted','NumResources','ResourceIDs', ...
    'ResourceSetID','WaveformPortCount','WaveformIndices','WaveformSymbols'},mapID);
maps=event.ResourceEvents;
assert(isstruct(resources)&&~isempty(resources)&&isstruct(maps)&&numel(maps)==numel(resources) && ...
    localFlag(event.Scheduled,mapID)&&localFlag(event.Transmitted,mapID) && ...
    event.NumResources==numel(resources)&&tx.CSIRSInfo.NumResources==numel(resources) && ...
    event.WaveformPortCount==columns && ...
    event.ResourceSetID==tx.CSIRSInfo.ResourceSetID && ...
    prepared.ReferenceIdentity.ResourceSetID==event.ResourceSetID && ...
    string(prepared.ReferenceIdentity.ResourceIDs)==string(event.ResourceIDs),mapID, ...
    'Require the original complete emitted resource set and column mapping.');
ids=double([resources.ResourceID]);
assert(all(isfinite(ids))&&all(ids>=0)&&all(ids==fix(ids))&&numel(unique(ids))==numel(ids) && ...
    isequal(ids(:),double(tx.CSIRSInfo.ResourceIDs(:))) && ...
    string(event.ResourceIDs)==strjoin(string(ids),'|'),mapID, ...
    'Preserve original ordered resource identities.');
allIndices=vertcat(resources.Indices); allSymbols=vertcat(resources.Symbols);
assert(isequal(allIndices,tx.CSIRSIndices)&&isequal(allSymbols,tx.CSIRSSymbols),mapID, ...
    'Original combined logical pilots must equal the retained resource population.');

components=struct('ResourceID',{},'ResourceSetID',{},'LogicalPortIndex0',{}, ...
    'ReferencePortNumber',{},'Samples',{},'WaveformColumnWeights',{});
componentEvidence=struct('ResourceID',{},'ResourceSetID',{},'LogicalPortIndex0',{}, ...
    'ReferencePortNumber',{},'LogicalIndicesSHA256',{},'LogicalSymbolsSHA256',{}, ...
    'WaveformPrecoderDigest',{},'WaveformColumnWeightsSHA256',{}, ...
    'UnscaledScalarWaveformSHA256',{},'ScaledScalarWaveformSHA256',{}, ...
    'ExpandedPreRFInputSHA256',{});
reconstructedGrid=zeros(size(grid),'like',grid);
reconstructedWaveform=zeros(size(waveform),'like',waveform);
reconstructedInput=zeros(size(transmitted),'like',transmitted);
occupied=zeros(0,1); mappedIndices=zeros(0,1); mappedSymbols=complex(zeros(0,1));
modulations=0;
for r=1:numel(resources)
    resource=resources(r); map=maps(r);
    localFields(resource,{'ResourceID','ResourceSetID','NumPorts','Indices','Symbols'},mapID);
    localFields(map,{'ResourceID','LogicalPortCount','WaveformPortCount', ...
        'WaveformPrecoderMatrix','WaveformPrecoderDigest','WaveformIndices','WaveformSymbols'},mapID);
    W=map.WaveformPrecoderMatrix; localArray(W,mapID);
    assert(ismatrix(W)&&size(W,1)==columns && size(W,2)==resource.NumPorts && ...
        map.LogicalPortCount==size(W,2)&&map.WaveformPortCount==columns && ...
        map.ResourceID==resource.ResourceID&&resource.ResourceSetID==event.ResourceSetID && ...
        string(map.WaveformPrecoderDigest)==sixgr.phy.mimo.MatrixContract.digest(W),mapID, ...
        'Bind the exact resource/port precoder; never replace it by a beam or rank.');
    indices=double(resource.Indices(:)); symbols=resource.Symbols(:);
    localArray(symbols,mapID);
    assert(~isempty(indices)&&numel(indices)==numel(symbols) && ...
        all(isfinite(indices))&&all(indices>=1)&&all(indices<=plane*size(W,2)) && ...
        all(indices==fix(indices))&&numel(unique(indices))==numel(indices),mapID, ...
        'Logical pilot indices must be unique, integer and inside their actual port domain.');
    logicalGrid=complex(zeros(K,L,size(W,2),'like',grid));
    logicalGrid(indices)=symbols;
    base=unique(mod(indices-1,plane)+1,'sorted');
    assert(isempty(intersect(base,occupied)),mapID,'Original CSI resources overlap.');
    occupied=[occupied;base]; %#ok<AGROW>
    logicalRE=reshape(logicalGrid,plane,[]);
    values=W*logicalRE(base,:).';
    indexMatrix=base+plane*(0:columns-1); valueMatrix=values.';
    active=abs(valueMatrix)>0;
    actualIndices=indexMatrix(active); actualSymbols=valueMatrix(active);
    assert(isequal(double(map.WaveformIndices(:)),actualIndices) && ...
        isequal(map.WaveformSymbols(:),actualSymbols),mapID, ...
        'Mapped resource event must equal the original logical pilots times the original precoder.');
    mappedIndices=[mappedIndices;actualIndices]; mappedSymbols=[mappedSymbols;actualSymbols]; %#ok<AGROW>
    for p=1:size(W,2)
        scalarGrid=logicalGrid(:,:,p); weights=cast(W(:,p),'like',grid);
        assert(any(scalarGrid~=0,'all'),mapID,'Every retained logical port must actually carry pilots.');
        componentGrid=reshape(reshape(scalarGrid,plane,1)*weights.',size(grid));
        reconstructedGrid=reconstructedGrid+componentGrid;
        % Direct native call with recorded parameters, NOT the canonical
        % wrapper (which can execute noise-calibration probes).
        [scalarWave,referenceInfo]=nrOFDMModulate(carrier,scalarGrid, ...
            'Nfft',double(ofdm.Nfft),'SampleRate',double(ofdm.SampleRate),'Windowing',0);
        modulations=modulations+1;
        for field=["Nfft","SampleRate","Windowing","CyclicPrefixLengths","SymbolLengths","SymbolPhases"]
            assert(isfield(ofdm,field)&&isfield(referenceInfo,field)&& ...
                isequaln(ofdm.(field),referenceInfo.(field)),opID, ...
                'Reference modulation differs from original native operator field %s.',field);
        end
        assert(isequal(size(scalarWave),[size(waveform,1) 1]) && ...
            strcmp(class(scalarWave),class(waveform)),opID, ...
            'Reference native OFDM changed sample count or scalar precision.');
        unscaled=scalarWave*weights.';
        scalarInput=scalarWave.*cast(scale,'like',scalarWave);
        expanded=scalarInput*weights.';
        reconstructedWaveform=reconstructedWaveform+unscaled;
        reconstructedInput=reconstructedInput+expanded;
        selected=floor((indices-1)/plane)==p-1;
        components(end+1)=struct('ResourceID',resource.ResourceID, ...
            'ResourceSetID',resource.ResourceSetID,'LogicalPortIndex0',p-1, ...
            'ReferencePortNumber',3000+p-1,'Samples',scalarInput, ...
            'WaveformColumnWeights',weights); %#ok<AGROW>
        componentEvidence(end+1)=struct('ResourceID',resource.ResourceID, ...
            'ResourceSetID',resource.ResourceSetID,'LogicalPortIndex0',p-1, ...
            'ReferencePortNumber',3000+p-1, ...
            'LogicalIndicesSHA256',localHash(indices(selected)), ...
            'LogicalSymbolsSHA256',localHash(symbols(selected)), ...
            'WaveformPrecoderDigest',string(map.WaveformPrecoderDigest), ...
            'WaveformColumnWeightsSHA256',localHash(weights), ...
            'UnscaledScalarWaveformSHA256',localHash(scalarWave), ...
            'ScaledScalarWaveformSHA256',localHash(scalarInput), ...
            'ExpandedPreRFInputSHA256',localHash(expanded)); %#ok<AGROW>
    end
end
assert(isequal(double(event.WaveformIndices(:)),mappedIndices)&& ...
    isequal(event.WaveformSymbols(:),mappedSymbols),mapID, ...
    'Combined mapped-event evidence must retain exactly the resource population.');
% Roundoff bound only: no receive-power or standards accuracy threshold.
tolerance=128*eps(class(waveform))*max(1,log2(double(ofdm.Nfft)))*numel(components);
closure=struct('Grid',localError(reconstructedGrid,grid), ...
    'UnscaledWaveform',localError(reconstructedWaveform,waveform), ...
    'ScaledPreRFInput',localError(reconstructedInput,transmitted), ...
    'RelativeTolerance',tolerance, ...
    'Scope',"floating_point_linearity_closure_not_power_accuracy");
assert(all([closure.Grid closure.UnscaledWaveform closure.ScaledPreRFInput]<=tolerance), ...
    closureID,'Original grid/waveform/input does not close under its retained logical-port decomposition.');
operator=struct('Engine',string(ofdm.EngineUsed),'Carrier',carrierRecord, ...
    'Nfft',double(ofdm.Nfft),'SampleRateHz',double(ofdm.SampleRate),'WindowingSamples',0, ...
    'CyclicPrefixLengths',double(ofdm.CyclicPrefixLengths), ...
    'SymbolLengths',double(ofdm.SymbolLengths),'SymbolPhases',double(ofdm.SymbolPhases));
evidence=struct('ContractVersion',"sixgr.csirs.pre_rf_port_reference_inputs/v1", ...
    'Source',"original_prepared_pilots_and_precoder_recorded_native_reference_modulation", ...
    'Scope',"mathematical_pre_RF_reference_components_not_separately_transmitted_ports", ...
    'InputPlane',"original_prepared_waveform_columns_before_composite_TX_RF", ...
    'PreparedResourceSchema',"configured_resource_set_with_original_Resources", ...
    'WaveformAmplitudeUnit',unit,'AmplitudeScale',double(scale), ...
    'AbsoluteSlotIndex0',prepared.Timeline.AbsoluteSlotIndex0, ...
    'NumSamples',size(waveform,1),'WaveformColumnCount',columns, ...
    'ResourceIDs',ids,'ResourceCount',numel(resources),'ComponentCount',numel(components), ...
    'OriginalGridSHA256',localHash(grid),'OriginalWaveformSHA256',localHash(waveform), ...
    'OriginalTransmitSamplesSHA256',localHash(transmitted), ...
    'OriginalPowerContextSHA256',sixgr.util.sha256Hex(char(jsonencode(power))), ...
    'HashSerialization',"WaveformHash.numeric_count_real_double_imag_double", ...
    'OriginalOperator',operator,'Components',componentEvidence,'Closure',closure, ...
    'AdditionalReferenceOFDMModulations',modulations,'AdditionalPhysicalTransmissions',0, ...
    'AdditionalRFExecutions',0,'AdditionalChannelExecutions',0, ...
    'AdditionalChannelEstimations',0,'AdditionalPowerContextApplications',0, ...
    'AdditionalCalibrationProbes',0,'ReferenceUsedByReceiver',false, ...
    'SeparatelyTransmittedPortSamples',false,'InstalledPhysicalOwnerBound',false, ...
    'MultiportReceivedPowerQualified',false,'StandardizedPowerAccuracyQualified',false);
token=string(jsonencode(evidence));
out=struct('Components',components,'Evidence',evidence,'EvidenceJSON',token, ...
    'EvidenceSHA256',sixgr.util.sha256Hex(char(token)));
end

function localFields(value,names,id)
assert(isstruct(value)&&isscalar(value)&&all(isfield(value,names)),id, ...
    'Missing original scalar-structure fields: %s.',strjoin(string(names),', '));
end
function value=localFlag(value,id)
assert(islogical(value)&&isscalar(value),id,'Original execution flags must be scalar logical values.');
end
function localArray(value,id)
assert(isfloat(value)&&~isempty(value)&&all(isfinite(value(:))),id, ...
    'Original samples, symbols and matrices must be finite floating-point arrays.');
end
function c=localCarrier(carrier,id)
assert(isa(carrier,'nrCarrierConfig')&&isscalar(carrier),id,'Require the original native carrier.');
c=struct();
for name=["NCellID","NSizeGrid","NStartGrid","SubcarrierSpacing","CyclicPrefix","NFrame","NSlot"]
    c.(name)=carrier.(name);
end
end
function value=localHash(value)
value=string(sixgr.phy.waveform.WaveformHash.numeric(value));
end
function value=localError(actual,expected)
value=norm(double(actual(:))-double(expected(:)))/max(norm(double(expected(:))),realmin);
end
