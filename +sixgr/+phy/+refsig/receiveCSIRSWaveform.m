function rx=receiveCSIRSWaveform(carrier,cfg,waveform,physicalWaveform,searchWindow,execution)
% Independently configured CSI-RS reception; no PDSCH assignment or decoder.
% Both inputs are actual, equally bounded receiver captures. Timing comes
% from the installed CSI-RS reference, not the TX waveform/channel delay.
arguments
    carrier (1,1) nrCarrierConfig
    cfg (1,1) struct
    waveform {mustBeNumeric,mustBeFinite,mustBeNonempty}
    physicalWaveform {mustBeNumeric,mustBeFinite,mustBeNonempty}
    searchWindow (1,2) double {mustBeInteger,mustBeNonnegative,mustBeFinite}
    execution (1,1) struct
end
assert(ismatrix(waveform) && isequal(size(waveform),size(physicalWaveform)), ...
    'sixgr:refsig:CSIReceivePlaneDimensions', ...
    'CSI-RS pre/post-front-end captures must have identical sample and antenna extents.');
[indices,symbols,referenceInfo]=sixgr.phy.refsig.csirs(carrier,cfg);
assert(~isempty(indices) && ~isempty(symbols), ...
    'sixgr:refsig:CSIReceiveOutsideConfiguredOccasion', ...
    'A CSI-RS receive obligation must use an enabled installed calendar occasion.');
enabled=sixgr.util.structGet(cfg,'phy.rx.cfoCorrectionEnabled',[]);
assert(isscalar(enabled) && (islogical(enabled)||isnumeric(enabled)) && ...
    any(double(enabled)==[0 1]),'sixgr:refsig:CSIReceiverFrequencyPolicyRequired', ...
    'Install explicit phy.rx.cfoCorrectionEnabled before CSI-RS reception.');
[aligned,timing,tracking]=localSynchronize( ...
    carrier,cfg,waveform,indices,symbols,referenceInfo,searchWindow,enabled);
% RX LO/timing stages occur AFTER the antenna connector. Their correction
% cannot be applied to an upstream capture that never experienced them.
% Synchronize each actual plane using installed pilots and its own samples;
% neither the injected RF parameters nor scoring references are estimates.
[physicalAligned,physicalTiming,physicalTracking]=localSynchronize( ...
    carrier,cfg,physicalWaveform,indices,symbols,referenceInfo,searchWindow,enabled);
[grid,gridInfo]=sixgr.phy.waveform.ofdmDemodulate(carrier,aligned);
[physicalGrid,physicalInfo]=sixgr.phy.waveform.ofdmDemodulate(carrier,physicalAligned);
received=struct('OFDMGrid',grid,'OFDMInfo',gridInfo);
options=struct('PhysicalMeasurementGrid',physicalGrid, ...
    'PhysicalMeasurementOFDMInfo',physicalInfo, ...
    'PhysicalMeasurementGridStatus',"available_exact_pre_front_end_grid", ...
    'PhysicalMeasurementReferencePlane',"supplied_receive_columns_pre_RX_front_end", ...
    'PhysicalMeasurementSource',"actual_independent_csirs_pre_front_end_capture", ...
    'ReceivedExecutionEvidence',execution);
rx=sixgr.phy.refsig.receiveCSIRSFromGrid(carrier,cfg,received,options);
% Preserve executed noise calibration for audit AFTER receiver estimation.
% These operands must never replace the receiver's measured disturbance.
rx.NoiseExecutionEvidence=struct();
for name=["AppliedAWGNSNR_dB","ReferenceAWGNGridNoiseVariance", ...
        "AbsoluteReferenceNoise","SampleRate_Hz","PowerContextDirection", ...
        "AbsoluteReferenceNoiseInjectedSampleVariance_mW","AbsoluteReferenceNoiseInjectionDomain", ...
        "PowerContextAmplitudeUnit","WaveformAmplitudeUnit","InjectedNoiseVariance", ...
        "InjectedNoiseVarianceDomain","InjectedNoiseVariancePreCompositeFrontEnd", ...
        "InjectedNoiseVariancePreCompositeFrontEndDomain", ...
        "RequestedReferenceEsN0_dB","ReferenceNoisePSD_mWPerHz", ...
        "ReferenceNoiseSampleVariance_mW","ReferenceNoiseSampleRate_Hz", ...
        "ReferenceNoiseContractSHA256","ReferenceNoiseSource","ReferenceNoiseReferencePlane", ...
        "ThermalNoiseApplied","ControlledReferenceNoiseApplied", ...
        "ReferenceAWGNSampleNoiseVariance","SignalEnergyPerOccupiedRE", ...
        "SampleToGridNoiseVarianceGain","NoiseOperatingMode", ...
        "AppliedAWGNSNRSource","AppliedAWGNSNRValueRole", ...
        "AWGNReferenceEnergySource","SharedNoiseCalibrationSource"]
    if isfield(execution,name)
        rx.NoiseExecutionEvidence.(name)=execution.(name);
    end
end
rx.ReceiveTiming=timing;
rx.ReceiverTrackingCorrection=tracking;
rx.PhysicalMeasurementReceiveTiming=physicalTiming;
rx.PhysicalMeasurementTrackingCorrection=physicalTracking;
rx.PhysicalMeasurementSynchronizationSource= ...
    "installed_CSI_RS_and_independent_pre_front_end_received_samples";
rx.ReceiverReferenceSource="installed_CSI_RS_configuration_and_received_waveform";
rx.PDSCHDecodeAttempted=false;
rx.RxGrid=grid;
rx.ReceiverOFDMInfo=gridInfo;
% Retain the ORIGINAL upstream measurement operator after estimation. This
% compact receipt is not a clean-signal reference, branch-layout proof or
% RSRP accuracy result. The receiver has no absolute observation identity;
% its sample coordinates remain explicitly relative to the supplied capture.
[receipt,probeAccounting]=localPhysicalDemodulationReceipt(carrier,cfg,physicalWaveform, ...
    physicalTiming,physicalTracking,physicalInfo,indices,symbols,referenceInfo);
rx.PhysicalMeasurementFFTCapabilityProbeAccounting=probeAccounting;
rx.PhysicalMeasurementDemodulationReceiptAvailable=true;
rx.PhysicalMeasurementDemodulationReceiptStatus=receipt.Status;
rx.PhysicalMeasurementDemodulationReceiptJSON=string(jsonencode(receipt));
rx.PhysicalMeasurementDemodulationReceiptSHA256=sixgr.util.sha256Hex( ...
    char(rx.PhysicalMeasurementDemodulationReceiptJSON));
if logical(sixgr.util.structGet(cfg,'measurements.csiSelectionQuality.Enabled',false))
    % Capture the actual receiver boundary, not a retrospective assertion
    % that the raw observation and the post-synchronization FFT input agree.
    rx.ReceiverSynchronizationEvidence=struct( ...
        'Source',"actual_CSI_RS_receiver_input_and_post_synchronization_FFT_input", ...
        'InputSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(waveform), ...
        'AlignedSHA256',string(gridInfo.WaveformSHA256), ...
        'InputHashSerialization',"WaveformHash.runtimeArray", ...
        'AlignedHashSerialization',"WaveformHash.numeric", ...
        'InputSampleCount',size(waveform,1),'AlignedSampleCount',size(aligned,1), ...
        'NumReceiveAntennas',size(waveform,2), ...
        'AppliedTimingCorrectionSamples',timing.AppliedTimingCorrectionSamples, ...
        'CFOCorrectionApplied',tracking.CFOCorrectionApplied, ...
        'CFOCorrectionApplied_Hz',tracking.CFOCorrectionApplied_Hz, ...
        'CFOPhaseOrigin',"observation_capture_start_zero_based", ...
        'ZeroPaddingUsed',timing.ReceiverZeroPaddingUsed);
end
end

function [receipt,probeAccounting]=localPhysicalDemodulationReceipt(carrier,cfg,input,timing,tracking,ofdm,indices,symbols,info)
probeAccounting=struct('IsolatedProbeDemodulationsThisCall',0,'OriginalCaptureDemodulations',0, ...
    'RFExecutions',0,'ChannelExecutions',0,'CacheHit',false);
% No additional ORIGINAL-capture acquisition/demodulation or grid in token.
% Independent capability probes are counted separately from measurement.
% Existing native hashes are reused. Only the original raw input is hashed
% here; the runtime owner may later bind it to its actual observation buffer.
id='sixgr:refsig:CSIPhysicalDemodulationReceipt';
required={'EngineUsed','Nfft','SampleRate','CyclicPrefixFraction', ...
    'SymbolLengths','CyclicPrefixLengths','WaveformSize','GridSize', ...
    'OFDMWindowingSamples','WaveformSHA256','GridSHA256'};
assert(all(isfield(ofdm,required)),id,'Retain the original native OFDM result metadata.');
K=12*double(carrier.NSizeGrid); L=double(carrier.SymbolsPerSlot);
assert(~timing.OracleTimingUsed && ~timing.ReceiverZeroPaddingUsed && ...
    timing.InputSampleCount==size(input,1) && ...
    ofdm.WaveformSize(1)==timing.DemodulatedSampleCount && ...
    ofdm.WaveformSize(2)==size(input,2) && ...
    ofdm.GridSize(1)==K && ofdm.GridSize(2)==L,id, ...
    'The receipt must describe the actual unpadded pre-front-end demodulation.');
unit=string(sixgr.util.structGet(cfg,'lls6g.runtimePowerContext.WaveformAmplitudeUnit',""));
assert(isscalar(unit)&&~ismissing(unit),id,'The supplied amplitude-unit declaration must be scalar text.');
unitSource="supplied_runtimePowerContext";
if strlength(unit)==0, unitSource="unavailable_missing_runtimePowerContext_unit"; end
resources=sixgr.util.structGet(info,'Resources',struct([]));
if isempty(resources)
    resources=struct('ResourceID',info.ResourceID,'Indices',indices,'Symbols',symbols, ...
        'NumPorts',info.NumCSIRSPorts,'RowNumber',info.RowNumber, ...
        'CDMType',info.CDMType,'RBOffset',info.RBOffset,'NumRB',info.NumRB);
end
parts=cell(numel(resources),1); supportParts=cell(numel(resources),1);
for k=1:numel(resources)
    r=resources(k); ind=double(r.Indices(:)); sym=r.Symbols;
    assert(~isempty(ind)&&numel(ind)==numel(sym)&&all(isfinite(ind))&& ...
        all(ind==fix(ind))&&all(ind>=1)&&all(ind<=K*L*double(r.NumPorts)),id, ...
        'Every installed resource must retain its original one-based logical-port pilot indices.');
    physical0=unique(mod(ind-1,K*L),'sorted');
    support=[mod(physical0,K) floor(physical0/K)];
    port0=unique(ind(ind<=K*L)-1,'sorted');
    portSupport=[mod(port0,K) floor(port0/K)];
    assert(~isempty(port0),id,'The original CSI-RS resource must include port 3000.');
    parts{k}=struct('ResourceID',double(r.ResourceID),'ResourceOrdinal0',k-1, ...
        'NumPorts',double(r.NumPorts),'RowNumber',double(r.RowNumber), ...
        'CDMType',string(r.CDMType),'RBOffset',double(r.RBOffset),'NumRB',double(r.NumRB), ...
        'LogicalPilotCount',numel(ind),'PhysicalRECount',size(support,1), ...
        'Port3000RECount',size(portSupport,1), ...
        'SelectedSymbols0',reshape(unique(support(:,2)),1,[]), ...
        'LogicalPilotIndicesSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(r.Indices), ...
        'LogicalPilotSymbolsSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(sym), ...
        'PhysicalSupportOrder',"ascending_subcarrier_plus_K_times_symbol", ...
        'PhysicalSupportSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(support), ...
        'Port3000SupportSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(portSupport));
    supportParts{k}=support;
end
allSupport=unique(vertcat(supportParts{:}),'rows','sorted');
selectedSymbols=reshape(unique(allSupport(:,2)),1,[]);
localSlot=mod(double(carrier.NSlot),double(carrier.SlotsPerSubframe));
slotPositions=localSlot*L+(1:L);
lengths=reshape(double(ofdm.SymbolLengths(slotPositions)),1,[]);
cp=reshape(double(ofdm.CyclicPrefixLengths(slotPositions)),1,[]);
fft=struct('Available',false,'Status',"unavailable_unqualified_native_FFT_operator", ...
    'RuntimeMATLABRelease',string(version('-release')), ...
    'EngineUsed',string(ofdm.EngineUsed),'Nfft',double(ofdm.Nfft), ...
    'SampleRateHz',double(ofdm.SampleRate),'CyclicPrefixFraction',double(ofdm.CyclicPrefixFraction), ...
    'CyclicPrefixLengths',cp,'SymbolLengths',lengths, ...
    'OFDMWindowingSamples',double(ofdm.OFDMWindowingSamples), ...
    'SelectedSymbols0',selectedSymbols,'FFTIntervals',zeros(0,2), ...
    'SampleCoordinateDomain',"relative_to_original_preRF_capture_start_zero_based_half_open", ...
    'SupportHashSerialization',"WaveformHash.runtimeArray_double_N_by_2_subcarrier0_symbol0", ...
    'ResourceSupportOrder',"lexicographic_subcarrier0_then_symbol0", ...
    'ResourceSupportSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(allSupport), ...
    'PhysicalRECount',size(allSupport,1),'FFTWindowRule',"");
% Qualify the exact runtime operator with isolated deterministic probes.
% Unsupported resampling/windowing stays unavailable, not guessed support.
if string(ofdm.EngineUsed)=="canonical_nrOFDMDemodulate" && ...
        ofdm.SampleRate==ofdm.Nfft*double(carrier.SubcarrierSpacing)*1000 && ...
        ofdm.OFDMWindowingSamples==0
    try
    probeAccounting.IsolatedProbeDemodulationsThisCall=NaN; % Failed probe call count is unavailable.
    [fft.NativeFFTCapability,probeAccounting]=sixgr.phy.waveform.nativeOFDMFFTCapability(carrier, ...
        double(ofdm.Nfft),double(ofdm.SampleRate),double(ofdm.CyclicPrefixFraction),L,0);
    assert(isequal(double(fft.NativeFFTCapability.SymbolLengths(:)),lengths(:)) && ...
        isequal(double(fft.NativeFFTCapability.CyclicPrefixLengths(:)),cp(:)),id, ...
        'Capability geometry must match the original executed native receipt.');
    fft.CapabilityProbeAccountingScope="isolated_proof_establishment_not_original_capture_demodulations";
    assert(all(lengths==cp+ofdm.Nfft)&&sum(lengths)==timing.DemodulatedSampleCount && ...
        isfinite(ofdm.CyclicPrefixFraction)&&ofdm.CyclicPrefixFraction>=0&& ...
        ofdm.CyclicPrefixFraction<=1,id,'Native FFT support must match the original aligned slot.');
    starts=[0 cumsum(lengths(1:end-1))];
    first=timing.AppliedTimingCorrectionSamples+starts(selectedSymbols+1)+ ...
        fix(cp(selectedSymbols+1)*ofdm.CyclicPrefixFraction);
    fft.FFTIntervals=[first(:) first(:)+ofdm.Nfft];
    assert(all(fft.FFTIntervals(:,1)>=0)&&all(fft.FFTIntervals(:,2)<=size(input,1)),id, ...
        'The original selected FFT windows must lie inside actual received samples.');
    fft.Available=true; fft.Status="retained_original_native_FFT_support";
    fft.FFTWindowRule="symbol_start_plus_fix_CP_times_fraction";
    catch capabilityFailure
        fft.Available=false; fft.Status="unavailable_native_FFT_capability";
        fft.CapabilityErrorIdentifier=string(capabilityFailure.identifier);
        fft.CapabilityErrorMessage=string(capabilityFailure.message);
    end
end
receipt=struct('ContractVersion',"sixgr.csirs.physical_demodulation/v2", ...
    'Status',"retained_practical_preRF_demodulation_not_independent_reference", ...
    'Source',"original_CSI_RS_physical_measurement_demodulation", ...
    'InputPlane',"supplied_pre_composite_receiver_front_end_capture", ...
    'InputSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(input), ...
    'InputHashSerialization',"WaveformHash.runtimeArray_class_dimensions_real_imag_double", ...
    'InputSize',size(input),'InputClass',string(class(input)), ...
    'AlignedSHA256',string(ofdm.WaveformSHA256),'AlignedSize',ofdm.WaveformSize, ...
    'GridSHA256',string(ofdm.GridSHA256),'GridSize',ofdm.GridSize, ...
    'AlignedAndGridHashSerialization',"WaveformHash.numeric_element_count_real_imag_double", ...
    'Carrier',struct('NCellID',double(carrier.NCellID),'NSizeGrid',double(carrier.NSizeGrid), ...
        'NStartGrid',double(carrier.NStartGrid),'SubcarrierSpacing_kHz',double(carrier.SubcarrierSpacing), ...
        'CyclicPrefix',string(carrier.CyclicPrefix),'NFrame',double(carrier.NFrame), ...
        'NSlot',double(carrier.NSlot)), ...
    'Timing',struct('Source',string(timing.TimingSource), ...
        'SearchWindowSamples',timing.SearchWindowSamples, ...
        'InitialTimingOffsetSamples',timing.InitialTimingOffsetSamples, ...
        'AppliedTimingCorrectionSamples',timing.AppliedTimingCorrectionSamples, ...
        'DemodulatedSampleCount',timing.DemodulatedSampleCount, ...
        'OracleTimingUsed',false,'ReceiverZeroPaddingUsed',false), ...
    'Frequency',struct('Source',string(tracking.Source),'Status',string(tracking.Status), ...
        'CFOEstimateAvailable',tracking.CFOEstimateAvailable,'EstimatedCFO_Hz',tracking.EstimatedCFO_Hz, ...
        'CFOCorrectionApplied',tracking.CFOCorrectionApplied, ...
        'CFOCorrectionApplied_Hz',tracking.CFOCorrectionApplied_Hz, ...
        'PhaseOrigin',"original_preRF_capture_start_zero_based"), ...
    'AdditionalOFDMDemodulationsScope',"original_received_capture_only_excludes_isolated_capability_probes", ...
    'FFTSupport',fft,'ResourceSetID',double(info.ResourceSetID), ...
    'Resources',{parts},'LogicalPilotHashSerialization',"WaveformHash.runtimeArray_original_class_and_dimensions", ...
    'NumReceiveChannels',size(input,2),'ReceiveChannelIndices0',0:size(input,2)-1, ...
    'ReceiveBranchLayoutQualified',false, ...
    'WaveformAmplitudeUnit',unit,'WaveformAmplitudeUnitSource',unitSource, ...
    'WaveformAmplitudeUnitRecognized',any(unit==["sqrt_mW","normalized_complex_baseband"]), ...
    'AbsoluteObservationIdentityBound',false,'IndependentPowerReferenceAvailable',false, ...
    'RSRPAccuracyQualified',false,'AdditionalTimingAcquisitions',0,'AdditionalOFDMDemodulations',0);
end

function [aligned,timing,tracking]=localSynchronize( ...
        carrier,cfg,waveform,indices,symbols,referenceInfo,searchWindow,enabled)
% The exact same practical algorithm is executed separately at each plane.
groups=localReferenceGroups(referenceInfo,indices);
[aligned,timing]=sixgr.phy.sync.alignULReferenceObservation( ...
    carrier,waveform,indices,symbols,searchWindow,groups);
initialTiming=timing;
ofdm=nrOFDMInfo(carrier);
tracking=struct('CFOEstimateAvailable',false,'EstimatedCFO_Hz',NaN, ...
    'CFOCorrectionApplied',false,'CFOCorrectionApplied_Hz',NaN, ...
    'Source',"receiver_cfo_correction_disabled_by_config", ...
    'Status',"disabled_by_config",'EstimateEvidence',struct());
if enabled
    method=lower(string(sixgr.util.structGet(cfg,'phy.impairments.cfoEstimationMethod',"")));
    assert(isscalar(method) && strlength(method)>0, ...
        'sixgr:refsig:CSIReceiverFrequencyPolicyRequired', ...
        'Enabled CSI-RS frequency correction needs phy.impairments.cfoEstimationMethod.');
    if any(method==["cyclic_prefix","cp"])
        % nrOFDMInfo can describe a subframe. The CP estimator needs the
        % exact captured slot, including its numerology-specific long CP.
        localSlot=mod(double(carrier.NSlot),double(carrier.SlotsPerSubframe));
        positions=localSlot*carrier.SymbolsPerSlot+(1:carrier.SymbolsPerSlot);
        slotInfo=ofdm;
        slotInfo.CyclicPrefixLengths=ofdm.CyclicPrefixLengths(positions);
        [frequency,evidence]=sixgr.phy.rx.estimateCFOFromCyclicPrefix( ...
            aligned,slotInfo,ofdm.SampleRate,sixgr.phy.rx.resolveCFOCPObservation(cfg));
        tracking.Source="cyclic_prefix_cfo_estimator";
    elseif any(method==["dmrs_two_symbol","dmrs","reference_symbol_phase_slope"])
        % The configured reference-phase method uses CSI-RS here, never
        % unknown PDSCH DM-RS. A one-symbol resource cannot supply a slope.
        grid=nrOFDMDemodulate(carrier,aligned);
        [frequency,evidence]=sixgr.phy.rx.estimateCFOFromReferenceSymbols( ...
            grid,indices,symbols,carrier,ofdm.SampleRate, ...
            'ReferenceGroupIDs',groups);
        tracking.Source="configured_csirs_reference_symbol_phase_slope";
    else
        error('sixgr:refsig:UnsupportedCSIReceiverFrequencyMethod', ...
            'CSI-RS cannot execute phy.impairments.cfoEstimationMethod=%s.',method);
    end
    tracking.EstimateEvidence=evidence;
    tracking.Status=string(evidence.Status);
    tracking.CFOEstimateAvailable=logical(evidence.EstimateAvailable) && isfinite(frequency);
    if tracking.CFOEstimateAvailable
        tracking.EstimatedCFO_Hz=frequency;
        rotation=exp(-1i*2*pi*frequency*(0:size(waveform,1)-1).'/ofdm.SampleRate);
        waveform=waveform.*cast(rotation,'like',waveform);
        [aligned,timing]=sixgr.phy.sync.alignULReferenceObservation( ...
            carrier,waveform,indices,symbols,searchWindow,groups);
        tracking.CFOCorrectionApplied=true;
        tracking.CFOCorrectionApplied_Hz=frequency;
    end
end
% Frequency estimation uses the first received-reference alignment; final
% demodulation can use a new alignment after CFO correction. Preserve both,
% instead of overwriting the alignment that supplied the frequency estimate.
tracking.InitialReceiveTiming=initialTiming;
tracking.FrequencyObservationStartSample=initialTiming.TimingOffsetSamples;
tracking.FrequencyObservationSampleCount=size(aligned,1);
tracking.FrequencyObservationSampleDomain="relative_to_observation_capture_start_zero_based";
timing.InitialTimingOffsetSamples=initialTiming.TimingOffsetSamples;
timing.TimingReestimatedAfterCFO=tracking.CFOCorrectionApplied;
end
function groups=localReferenceGroups(info,indices)
% Calendar/resource identity is receiver-installed configuration authority.
% Distinct CSI-RS resources may use different beams even at the same k/port.
if isfield(info,'Resources') && ~isempty(info.Resources)
    pieces=cell(numel(info.Resources),1);
    groupIndices=cell(numel(info.Resources),1);
    for n=1:numel(info.Resources)
        resource=info.Resources(n);
        groupIndices{n}=resource.Indices;
        pieces{n}=repmat(double(resource.ResourceID),size(resource.Indices));
    end
    combined=vertcat(groupIndices{:});
    assert(isequal(combined(:),indices(:)), ...
        'sixgr:refsig:CSIReferenceResourceIdentityMismatch', ...
        'Combined CSI-RS references must preserve installed resource identity/order.');
    groups=vertcat(pieces{:});
    groups=groups(:);
else
    groups=repmat(double(info.ResourceID),numel(indices),1);
end
end
