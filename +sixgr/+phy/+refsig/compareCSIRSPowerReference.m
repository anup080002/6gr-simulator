function result=compareCSIRSPowerReference(grid,support,nfft,measuredSignedPower,waveformAmplitudeUnit)
%COMPARECSIRSPOWERREFERENCE Pure, explicitly unit-scoped reference arithmetic.
% grid is the raw, unnormalized native FFT of a supplied reference capture;
% support contains its unique zero-based [subcarrier symbol] port-3000 REs.
% The caller, NOT this function, must prove original capture ownership,
% component/port isolation, the recorded noisy-receiver CFO/timing/FFT
% operator, receive-column ordering and the declared waveform amplitude unit.
% No estimator is run on the reference and no gain/EPRE/precoder is reapplied.
%
% sqrt_mW: native FFT / (Nfft*sqrt(1000)) gives sqrt(W) per RE.
% normalized_complex_baseband: raw-grid power stays in unit-RE units, not W.
% Signed noise-debiased measurements are retained, never clipped. Logarithmic
% errors require positive measured AND reference power. A zero reference is
% valid linear power and has log power -Inf, but no defined power ratio.
% This arithmetic alone establishes neither independent port attribution nor
% a standardized receiver reference plane, accuracy qualification or delivery.
id='sixgr:refsig:CSIRSPowerReferenceOperands';
assert((isa(grid,'double')||isa(grid,'single')) && ~issparse(grid) && ...
    ~isempty(grid) && ndims(grid)<=3 && all(isfinite(grid),'all'),id, ...
    'Require a finite, nonempty raw native FFT grid with receive columns in dimension three.');
K=size(grid,1); L=size(grid,2); R=size(grid,3);
assert(isnumeric(nfft) && isreal(nfft) && isscalar(nfft) && isfinite(nfft) && ...
    nfft>=K && nfft==fix(nfft),id,'Nfft must be an integer covering the supplied carrier grid.');
assert(isnumeric(support) && isreal(support) && ismatrix(support) && ...
    ~isempty(support) && size(support,2)==2 && all(isfinite(support),'all') && ...
    all(support>=0,'all') && all(support==fix(support),'all') && ...
    all(support(:,1)<K) && all(support(:,2)<L) && ...
    size(unique(support,'rows'),1)==size(support,1),id, ...
    'Use each supplied port-3000 physical RE exactly once, with in-bounds zero-based integer coordinates.');
assert(isnumeric(measuredSignedPower) && isreal(measuredSignedPower) && ...
    isvector(measuredSignedPower) && numel(measuredSignedPower)==R && ...
    all(isfinite(measuredSignedPower),'all'),id, ...
    'Retain exactly one finite signed measured power per original receive column.');
unitID='sixgr:refsig:CSIRSPowerReferenceUnit';
assert((isstring(waveformAmplitudeUnit) && isscalar(waveformAmplitudeUnit) && ...
    ~ismissing(waveformAmplitudeUnit)) || ...
    (ischar(waveformAmplitudeUnit) && isrow(waveformAmplitudeUnit)),unitID, ...
    'The original waveform amplitude unit must be explicitly supplied.');
unit=string(waveformAmplitudeUnit);
assert(any(unit==["sqrt_mW","normalized_complex_baseband"]),unitID, ...
    'No absolute power conversion exists for this waveform amplitude unit.');

indices=sub2ind([K L],double(support(:,1))+1,double(support(:,2))+1);
flat=reshape(grid,K*L,R);
values=double(flat(indices,:));
absolute=unit=="sqrt_mW";
scale=1;
powerUnit="unit_RE";
if absolute
    scale=double(nfft)*sqrt(1000);
    powerUnit="W";
end
reference=mean(abs(values/scale).^2,1);
measured=double(measuredSignedPower(:).');
linearError=measured-reference;
assert(all(isfinite(reference)) && all(isfinite(linearError)),id, ...
    'Finite supplied operands must yield finite reference and linear-error powers.');
referenceLog=10*log10(reference); % Zero reference is valid and stays -Inf.
measuredLog=nan(1,R);
measuredPositive=measured>0;
measuredLog(measuredPositive)=10*log10(measured(measuredPositive));
valid=measuredPositive & reference>0;
errors=nan(1,R);
errors(valid)=measuredLog(valid)-referenceLog(valid);
[referenceMaximum,referenceColumn]=max(reference);
[measuredSignedMaximum,measuredColumn]=max(measured);
measuredReportingAvailable=measuredSignedMaximum>0;
referencePositive=referenceMaximum>0;
referenceSelectedColumn=NaN;
if referencePositive, referenceSelectedColumn=referenceColumn-1; end
measuredSelectedColumn=NaN;
measuredReported=NaN;
referenceAtMeasuredSelected=NaN;
selectedError=NaN;
if measuredReportingAvailable
    measuredSelectedColumn=measuredColumn-1;
    measuredReported=measuredSignedMaximum;
    referenceAtMeasuredSelected=reference(measuredColumn);
    selectedError=errors(measuredColumn);
end
reportedError=NaN;
if measuredReportingAvailable && referencePositive
    reportedError=10*log10(measuredSignedMaximum)-10*log10(referenceMaximum);
end
referenceDBm=nan(1,R); measuredDBm=nan(1,R);
if absolute
    referenceDBm=referenceLog+30;
    measuredDBm=measuredLog+30;
end
result=struct( ...
    'ContractVersion',"sixgr.refsig.CSIRSPowerReferenceComparison/v1", ...
    'Source',"supplied_raw_native_FFT_port3000_support_arithmetic", ...
    'ReferencePlane',"caller_supplied_not_established_by_arithmetic", ...
    'WaveformAmplitudeUnit',unit,'LinearPowerUnit',powerUnit, ...
    'NativeFFTSize',double(nfft),'RawGridAmplitudeDivisor',scale, ...
    'PhysicalPortNumber',3000,'ReferenceRECount',size(support,1), ...
    'ReceiveColumnCount',R,'ColumnIndexBase',0, ...
    'ReferencePerReceiveColumn',reference, ...
    'MeasuredSignedPerReceiveColumn',measured, ...
    'LinearErrorPerReceiveColumn',linearError, ...
    'ReferenceLogPower_dB',referenceLog,'MeasuredLogPower_dB',measuredLog, ...
    'ReferencePower_dBm',referenceDBm,'MeasuredPower_dBm',measuredDBm, ...
    'PerReceiveColumnError_dB',errors,'PerReceiveColumnErrorDefined',valid, ...
    'MeasuredSignedMaximumPower',measuredSignedMaximum, ...
    'MeasuredReportingAvailable',measuredReportingAvailable, ...
    'MeasuredReportedPower',measuredReported,'ReferenceMaximumPower',referenceMaximum, ...
    'MeasuredSelectedColumn0',measuredSelectedColumn, ...
    'ReferenceSelectedColumn0',referenceSelectedColumn, ...
    'ReferenceAtMeasuredSelectedColumn',referenceAtMeasuredSelected, ...
    'MeasuredSelectedColumnError_dB',selectedError,'ReportedError_dB',reportedError, ...
    'ReportingAggregation',"separate_positive_maximum_receive_column_implementation_policy", ...
    'ReportedErrorDefinition',"measured_max_log_power_minus_reference_max_log_power", ...
    'SelectedColumnErrorDefinition',"measured_selected_column_log_power_minus_same_reference_column", ...
    'PowerComparisonPerformed',true,'MeasuredPowerClipped',false, ...
    'SharedOwnerBound',false,'ComponentIsolationProved',false, ...
    'IndependentPortAttributionProved',false,'StandardizedRSRPAccuracyQualified',false, ...
    'HardwareQualified',false);
end
