function [resourceID, cri] = resolveCSIResourceIdentity(cfg, value, inputKind)
%RESOLVECSIRESOURCEIDENTITY Keep configured NZP CSI-RS IDs and CRI distinct.
% TS 38.214 V18.8.0 section 5.2.1.4.2: CRI k identifies entry k+1 of
% the configured resource list. Never sort that list or infer an ID from k.
% inputKind is explicit: "resource_id" or "cri". Preserve input shape.

ids = sixgr.util.structGet(cfg, "phy.csirs.resourceIDs", []);
count = sixgr.util.structGet(cfg, "phy.csirs.numResources", []);
assert(isnumeric(count) && isreal(count) && isscalar(count) && ...
    isfinite(count) && count >= 1 && count == fix(count) && ...
    isnumeric(ids) && isreal(ids) && isvector(ids) && ...
    numel(ids) == count && all(isfinite(ids(:))) && ...
    all(ids(:) >= 0 & ids(:) <= flintmax & ids(:) == fix(ids(:))) && ...
    numel(unique(ids)) == count, ...
    'sixgr:phy:refsig:InvalidCSIResourceIDs', ...
    ['phy.csirs.resourceIDs must contain numResources unique finite ' ...
     'nonnegative integer IDs in configured resource-list order.']);
assert(isnumeric(value) && isreal(value) && isvector(value) && ...
    ~isempty(value) && all(isfinite(value(:))) && ...
    all(value(:) >= 0 & value(:) <= flintmax & value(:) == fix(value(:))), ...
    'sixgr:phy:refsig:InvalidCSIResourceIndex', ...
    'CSI resource identity input must contain finite nonnegative integers.');
inputKind = string(inputKind);
assert(isscalar(inputKind) && any(inputKind == ["resource_id","cri"]), ...
    'sixgr:phy:refsig:InvalidCSIResourceIdentityDomain', ...
    'CSI identity inputKind must explicitly be resource_id or cri.');
ids = double(ids);
value = double(value);
if inputKind == "resource_id"
    [known, ordinal] = ismember(value, ids);
    assert(all(known(:)), 'sixgr:phy:refsig:UnknownCSIResourceID', ...
        'Every CSI resource ID must occur in the installed phy.csirs.resourceIDs list.');
    resourceID = value;
    cri = double(ordinal) - 1;
else
    assert(all(value(:) < count), ...
        'sixgr:phy:refsig:CSIResourceOrdinalOutOfRange', ...
        'CRI must be a zero-based resource-list position in [0,%d].', count - 1);
    cri = value;
    resourceID = reshape(ids(cri + 1), size(value));
end
end
