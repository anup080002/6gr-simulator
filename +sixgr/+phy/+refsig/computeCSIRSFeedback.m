function [csi, info] = computeCSIRSFeedback(carrier, cfg, reception)
%COMPUTECSIRSFEEDBACK Derive RI/PMI/CQI/CRI from received CSI-RS only.
% The installed report and DM-RS configuration define the report format;
% no PDSCH grant, DCI decision, decoder result, or transmitted payload is
% used to select the reported values.
arguments
    carrier (1,1) nrCarrierConfig
    cfg (1,1) struct
    reception (1,1) struct
end

measurement = sixgr.util.structGet(reception, "CSIMeasurementState", []);
if ~isa(measurement, "sixgr.phy.mimo.CSIMeasurementState")
    error("sixgr:refsig:MissingCSIRSMeasurementState", ...
        "Independent CSI reporting requires the immutable received CSI-RS measurement state.");
end
if ~logical(sixgr.util.structGet( ...
        reception, "CSIRSObservation.ChannelEstimateAvailable", false))
    error("sixgr:refsig:MissingCSIRSChannelEstimate", ...
        "Independent CSI reporting requires a completed CSI-RS channel estimate.");
end
selectedCSIRS = sixgr.util.structGet(reception, "SelectedCSIRS", []);
if ~isa(selectedCSIRS, "nrCSIRSConfig")
    error("sixgr:refsig:MissingSelectedCSIRSConfig", ...
        "The measured CSI report must retain its selected installed CSI-RS resource.");
end

% The report engine needs the installed PDSCH DM-RS port convention for
% Type-II/high-port codebooks.  Build that configuration without allocating
% PDSCH REs.  Calling dmrsPDSCH here is incorrect: its cfg overload invokes
% allocREsPDSCH, applies occasion-owned SSB/CSI-RS reservations, and can fail
% on a perfectly valid cell-common CSI-RS occasion where no PDSCH exists.
% CSI reporting consumes installed DM-RS semantics, not a fabricated grant.
pdsch = sixgr.phy.grid.pdschConfigFromConfig(carrier, cfg);
reportConfiguration = sixgr.util.structGet( ...
    cfg, "phy.csi.reportConfiguration", []);
if isempty(reportConfiguration)
    error("sixgr:refsig:MissingCSIReportConfiguration", ...
        "Independent CSI reporting requires the installed report configuration.");
end

args = {"Direction", "DL", ...
    "MeasurementState", measurement, ...
    "ReportConfiguration", reportConfiguration, ...
    "Carrier", carrier, ...
    "CSIRSConfig", selectedCSIRS, ...
    "PDSCHDMRSConfig", pdsch.DMRS, ...
    "FullChannelEstimate", sixgr.util.structGet( ...
        reception, "CSIRSChannelEstimate", [])};
receivedGrid = sixgr.util.structGet(reception, "RxGrid", []);
referenceIndices = sixgr.util.structGet(reception, "CSIRSIndices", []);
referenceSymbols = sixgr.util.structGet(reception, "CSIRSSymbols", []);
if ~isempty(receivedGrid) && ~isempty(referenceIndices) && ...
        ~isempty(referenceSymbols)
    args = [args, {"ReceivedGrid", receivedGrid, ...
        "ReferenceIndices", referenceIndices, ...
        "ReferenceSymbols", referenceSymbols}];
end
[csi, engineInfo] = sixgr.phy.dl.CSI_Feedback( ...
    measurement.ChannelEstimate, measurement.NoiseVariance, cfg, args{:});

observation = sixgr.util.structGet(reception, "CSIRSObservation", struct());
csi.ReferenceMeasuredSINR_dB = double(sixgr.util.structGet( ...
    observation, "ReferenceMeasuredSINR_dB", NaN));
csi.ReferenceMeasuredSINRSource = string(sixgr.util.structGet( ...
    observation, "ReferenceMeasuredSINRSource", ""));
csi.ReferenceMeasuredSINRStatus = string(sixgr.util.structGet( ...
    observation, "ReferenceMeasuredSINRStatus", "not_attempted"));
csi.ReferenceSINRMeasurementDomain = string(sixgr.util.structGet( ...
    observation, "SINRMeasurementDomain", ""));
csi.MeasuredRSRP_dBm = double(sixgr.util.structGet( ...
    observation, "MeasurementRSRP_dBm", NaN));
csi.MeasuredRSSI_dBm = double(sixgr.util.structGet( ...
    observation, "MeasurementRSSI_dBm", NaN));
csi.MeasuredRSRQ_dB = double(sixgr.util.structGet( ...
    observation, "MeasurementRSRQ_dB", NaN));
csi.MeasurementPowerReferencePlane = string(sixgr.util.structGet( ...
    observation, "PowerReferencePlane", ""));
csi.MeasurementSource = string(sixgr.util.structGet( ...
    observation, "MeasurementSource", ""));
csi.CSIMeasurementID = string(measurement.MeasurementID);
csi.CSIMeasurementDigest = string(measurement.Digest);
csi.CSIMeasurementProvenance = string(measurement.Provenance);
csi.CSIMeasurementSlot = double(measurement.Slot);

info = struct( ...
    "ExecutionEngine", string(sixgr.util.structGet( ...
        engineInfo, "EngineUsed", "sixgr.phy.dl.CSI_Feedback")), ...
    "MeasurementID", string(measurement.MeasurementID), ...
    "MeasurementDigest", string(measurement.Digest), ...
    "MeasurementNoiseVariance", double(measurement.NoiseVariance), ...
    "PDSCHDecodeAttempted", false, ...
    "PDSCHResourceAllocationAttempted", false, ...
    "DCIConsumed", false, ...
    "HARQStateConsumed", false, ...
    "Source", "received_csirs_independent_report_engine");
end
