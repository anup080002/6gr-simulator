function evidence=measureCSIRSCDMPortPower(carrier,reference,receivedGrid,cdm,disturbance)
% Port-3000 received power from local CDM despreading, not smoothed Hest.
% The disturbance must come from the disjoint configured CSI-IM resource.
% For one CDM tile, g=w*y and E|g|^2=|g_signal|^2+v*sum(abs(w).^2)
% under locally uncorrelated disturbance. Average powers of separate tiles;
% never coherently average a frequency-selective channel across the band.
% This is a practical measurement model, not a detector or a channel oracle.
K=12*double(carrier.NSizeGrid); L=double(carrier.SymbolsPerSlot);
nRx=size(receivedGrid,3); ports=size(reference,3);
assert(size(reference,1)==K && size(reference,2)==L && ...
    size(receivedGrid,1)==K && size(receivedGrid,2)==L && ...
    ndims(reference)<=3 && ndims(receivedGrid)<=3, ...
    'sixgr:refsig:CSICDMPowerDimensions','Require matching received and known-reference slot grids.');
validateattributes(cdm,{'numeric'},{'vector','numel',2,'integer','positive','finite'});
validateattributes(disturbance,{'numeric'},{'vector','numel',nRx,'nonnegative','finite'});
X=reshape(double(reference),K*L,ports);
Y=reshape(double(receivedGrid),K*L,nRx);
assert(all(isfinite(X),'all') && all(isfinite(Y),'all'), ...
    'sixgr:refsig:CSICDMPowerNonfinite','Reference and received samples must be finite.');
remaining=X(:,1)~=0; referenceCount=nnz(remaining);
assert(referenceCount>0,'sixgr:refsig:CSICDMPowerMissingPort','Port 3000 has no reference REs.');
rawSum=zeros(1,nRx); unitBiasSum=0; groups=0;
% Retain the operator and coefficients from THIS practical execution. The
% arrays scale with the port-3000 pilot population, not the whole slot IQ.
% Explicit real/imaginary fields keep subsequent JSON serialization exact.
tileSize=prod(double(cdm)); capacity=ceil(referenceCount/tileSize);
tileIndices=zeros(tileSize,capacity);
weightsReal=zeros(tileSize,capacity); weightsImag=zeros(tileSize,capacity);
energies=zeros(capacity,1); noiseGains=zeros(capacity,1);
coefficientsReal=zeros(capacity,nRx); coefficientsImag=zeros(capacity,nRx);
while any(remaining)
    first=find(remaining,1); [k,l]=ind2sub([K L],first);
    [kk,ll]=ndgrid(k+(0:cdm(1)-1),l+(0:cdm(2)-1));
    assert(all(kk<=K & ll<=L,'all'), ...
        'sixgr:refsig:CSICDMPowerTile','CDM tile exceeds the received slot.');
    tile=sub2ind([K L],kk(:),ll(:));
    assert(all(remaining(tile)), ...
        'sixgr:refsig:CSICDMPowerTile','Port-3000 reference must contain complete, nonoverlapping CDM tiles.');
    pilot=X(tile,1); energy=sum(abs(pilot).^2);
    weights=conj(pilot)/energy;
    projection=weights.'*X(tile,:);
    assert(abs(projection(1)-1)<1e-12 && all(abs(projection(2:end))<1e-12), ...
        'sixgr:refsig:CSICDMPowerOrthogonality','Installed CDM references must separate port 3000 from other ports.');
    coefficient=weights.'*Y(tile,:);
    % energy=tile RE count times its mean reference-symbol energy.
    rawSum=rawSum+energy*abs(coefficient).^2;
    noiseGain=sum(abs(weights).^2);
    unitBiasSum=unitBiasSum+energy*noiseGain;
    ordinal=groups+1;
    tileIndices(:,ordinal)=tile;
    weightsReal(:,ordinal)=real(weights); weightsImag(:,ordinal)=imag(weights);
    energies(ordinal)=energy; noiseGains(ordinal)=noiseGain;
    coefficientsReal(ordinal,:)=real(coefficient); coefficientsImag(ordinal,:)=imag(coefficient);
    remaining(tile)=false; groups=groups+1;
end
raw=rawSum/referenceCount;
unitBias=unitBiasSum/referenceCount;
bias=unitBias*double(disturbance(:).');
evidence=struct('RawPort3000PowerPerBranch',raw, ...
    'EstimatedNoiseBiasPerBranch',bias,'SignedPort3000PowerPerBranch',raw-bias, ...
    'UnitDisturbancePowerBias',unitBias,'PilotCount',referenceCount, ...
    'CDMGroupCount',groups,'CDMLengths',double(cdm(:).'), ...
    'ClippedToNonnegative',false, ...
    'NoiseBiasModel',"locally_uncorrelated_disturbance_CSI_IM_matched_second_moment", ...
    'SignalModel',"per_CDM_tile_effective_channel_no_wideband_coherent_average", ...
    'RatioInterpretation',"signed_power_debiased_not_unbiased_ratio_dB_or_selected_max", ...
    'Source',"received_CDM_despread_CSI_IM_noise_debiased_port3000_reference_RE_power");
% No new coefficient or receiver estimate is computed for this receipt.
% Geometry reconstruction is unnecessary: later diagnostics can apply the
% original weights in the original order, then verify their Y coefficients
% and powers against these actual values before using model components.
hash=@sixgr.phy.waveform.WaveformHash.runtimeArray;
usedIndices=reshape(tileIndices(:,1:groups),[],1);
typedInput=reshape(receivedGrid,K*L,nRx);
typedReference=reshape(reference,K*L,ports);
inputSupport=typedInput(usedIndices,:); referenceSupport=typedReference(usedIndices,:);
inputHash=hash(inputSupport); referenceHash=hash(referenceSupport);
arithmeticInputHash=inputHash; arithmeticReferenceHash=referenceHash;
if ~isa(receivedGrid,'double'), arithmeticInputHash=hash(double(inputSupport)); end
if ~isa(reference,'double'), arithmeticReferenceHash=hash(double(referenceSupport)); end
receipt=struct('ContractVersion',"sixgr.csirs.original_cdm_projection/v1", ...
    'Source',"original_practical_CDM_port3000_projection", ...
    'RequirementClass',"IMPLEMENTATION_POLICY", ...
    'InputPlane',"supplied_CSI_measurement_grid_not_waveform", ...
    'InputGridClass',string(class(receivedGrid)),'InputGridSize',double(size(receivedGrid)), ...
    'InputUsedSupportSHA256',inputHash, ...
    'ReferenceGridClass',string(class(reference)),'ReferenceGridSize',double(size(reference)), ...
    'ReferenceUsedSupportSHA256',referenceHash, ...
    'UsedSupportSerializationOrder',"TileIndices1Based_column_major_then_original_receive_or_reference_columns", ...
    'ArithmeticInputUsedSupportSHA256',arithmeticInputHash, ...
    'ArithmeticReferenceUsedSupportSHA256',arithmeticReferenceHash, ...
    'ArithmeticInputHashReusesTypedSupportHash',isa(receivedGrid,'double'), ...
    'ArithmeticReferenceHashReusesTypedSupportHash',isa(reference,'double'), ...
    'ArithmeticClass',"double", ...
    'SampleHashSerialization',"WaveformHash.runtimeArray_class_dimensions_real_imag_double", ...
    'CarrierIdentity',struct('NSizeGrid',double(carrier.NSizeGrid), ...
        'NStartGrid',double(carrier.NStartGrid),'SubcarrierSpacing',double(carrier.SubcarrierSpacing), ...
        'NSlot',double(carrier.NSlot),'NFrame',double(carrier.NFrame), ...
        'SymbolsPerSlot',double(carrier.SymbolsPerSlot)), ...
    'ReferencePortNumber',3000,'ReferencePortCount',ports,'ReceiveColumnCount',nRx, ...
    'ReceiveColumnIndices0',0:nRx-1,'CDMLengths',double(cdm(:).'), ...
    'TileCount',groups,'TileSize',tileSize,'NormalizationPilotCount',referenceCount, ...
    'TileIndices1Based',tileIndices(:,1:groups), ...
    'ProjectionWeightsReal',weightsReal(:,1:groups),'ProjectionWeightsImag',weightsImag(:,1:groups), ...
    'ReferenceEnergyPerTile',energies(1:groups),'UnitNoiseGainPerTile',noiseGains(1:groups), ...
    'ProjectedCoefficientsReal',coefficientsReal(1:groups,:), ...
    'ProjectedCoefficientsImag',coefficientsImag(1:groups,:), ...
    'WeightedSquaredCoefficientSumPerBranch',rawSum,'UnitNoiseBiasWeightedSum',unitBiasSum, ...
    'RawPort3000PowerPerBranch',raw,'DisturbancePowerPerBranch',double(disturbance(:).'), ...
    'UnitDisturbancePowerBias',unitBias,'EstimatedNoiseBiasPerBranch',bias, ...
    'SignedPort3000PowerPerBranch',evidence.SignedPort3000PowerPerBranch, ...
    'ProjectionConvention',"weights_nonconjugating_transpose_times_received_tile", ...
    'WeightDefinition',"conj_original_port3000_pilot_divided_by_original_tile_pilot_energy", ...
    'AccumulationOrder',"increasing_first_unconsumed_port3000_linear_index_then_sequential_tile_sum", ...
    'PowerNormalization',"sum_tile_energy_times_abs_coefficient_squared_divided_by_original_pilot_count", ...
    'NoiseBiasModel',evidence.NoiseBiasModel,'ClippedToNonnegative',false, ...
    'WaveformAmplitudeUnitBound',false,'ResourceIdentityBound',false,'OriginalSharedOwnerBound',false, ...
    'IndependentReferenceAvailable',false,'StandardizedAccuracyQualified',false, ...
    'ReferenceUsedByReceiver',false);
evidence.CDMProjectionReceipt=receipt;
evidence.CDMProjectionReceiptSHA256=sixgr.util.sha256Hex(char(jsonencode(receipt)));
end
