function out=compareCSIRSSINRReference(desiredGrid,receivedGrid,support,nfft,measured,unit)
%COMPARECSIRSSINRREFERENCE Post-reception arithmetic, never a CSI estimator.
% Caller must prove original desired/received samples and the SAME recorded
% receiver operator. The arithmetic alone establishes neither that proof nor
% standardized accuracy. Desired includes the caller's declared TX-RF scope.
% Residual is T(original composite)-T(original desired); no noise is redrawn.
% TS 38.215 5.1.6: ratio of linear resource averages, with dedicated CSI-IM
% support when configured, otherwise the CSI-RS support. Branches stay apart.
id='sixgr:refsig:CSIRSSINRReferenceOperands';
assert(isstruct(measured)&&isscalar(measured)&& ...
    isnumeric(receivedGrid)&&isequal(size(receivedGrid),size(desiredGrid))&& ...
    all(isfinite(receivedGrid),'all'),id,'Use matching finite original grids.');
nrx=size(desiredGrid,3);
for name=["DesiredPowerPerReceiveAntenna","NoiseInterferencePowerPerReceiveAntenna", ...
        "CSI_SINRPerReceiveAntenna_dB","ReceiveBranch1Based","CSI_SINR_dB", ...
        "SignalPowerEstimation","InterferenceMeasurement","Source","DisturbanceSource"]
    assert(isfield(measured,name),id,'Missing original SINR operand %s.',name);
end
assert(isfield(measured,'ReferencePort')&&realScalar(measured.ReferencePort)&& ...
    isequal(double(measured.ReferencePort),3000)&& ...
    isfield(measured,'ReferenceRECount')&&realScalar(measured.ReferenceRECount)&& ...
    isequal(double(measured.ReferenceRECount),size(support,1)), ...
    id,'Bind SINR to the original port-3000 resource and exact RE count.');
for name=["DesiredPowerPerReceiveAntenna","NoiseInterferencePowerPerReceiveAntenna", ...
        "CSI_SINRPerReceiveAntenna_dB"]
    value=measured.(name);
    assert(isnumeric(value)&&isreal(value)&&~issparse(value)&&isvector(value)&&numel(value)==nrx, ...
        id,'Original %s must be a numeric receive-column vector, not coerced text.',name);
end
assert(realScalar(measured.CSI_SINR_dB)&&realScalar(measured.ReceiveBranch1Based)&& ...
    isstruct(measured.SignalPowerEstimation)&&isscalar(measured.SignalPowerEstimation),id, ...
    'Original reported SINR/branch must be numeric scalars and estimator metadata one structure.');
ps=double(measured.DesiredPowerPerReceiveAntenna(:).');
pn=double(measured.NoiseInterferencePowerPerReceiveAntenna(:).');
assert(numel(ps)==nrx&&numel(pn)==nrx&&isreal(ps)&&isreal(pn)&& ...
    all(isfinite(ps))&&all(isfinite(pn))&&all(pn>=0),id, ...
    'Retain signed signal estimates and nonnegative disturbance per receive column.');
% Reuse the strictly validated exact-resource power arithmetic, including
% the native raw-grid to sqrt(W) scaling. No layer/branch factor is invented.
p=sixgr.phy.refsig.compareCSIRSPowerReference(desiredGrid,support,nfft,ps,unit);
residual=receivedGrid-desiredGrid;
im=measured.InterferenceMeasurement;
assert(isstruct(im)&&isscalar(im)&&isfield(im,'Plan')&& ...
    isstruct(im.Plan)&&isscalar(im.Plan)&&isfield(im.Plan,'Enabled'),id,'Retain original CSI-IM policy.');
assert(booleanScalar(im.Plan.Enabled),id, ...
    'CSI-IM enabled state must be an explicit scalar boolean.');
noiseSupport=support; dedicated=logical(im.Plan.Enabled);
if dedicated
    assert(isfield(im,'Available')&&booleanScalar(im.Available)&&im.Available&& ...
        isfield(im.Plan,'Scheduled')&&booleanScalar(im.Plan.Scheduled)&&im.Plan.Scheduled&& ...
        isfield(im,'SampleCount')&&realScalar(im.SampleCount)&& ...
        isfield(im.Plan,'NumRE')&&realScalar(im.Plan.NumRE)&& ...
        isfield(im.Plan,'PhysicalIndices1Based')&&isnumeric(im.Plan.PhysicalIndices1Based)&& ...
        isreal(im.Plan.PhysicalIndices1Based)&&isvector(im.Plan.PhysicalIndices1Based)&& ...
        ~issparse(im.Plan.PhysicalIndices1Based),id,'Configured CSI-IM must have original numeric support/counts.');
    idx=double(im.Plan.PhysicalIndices1Based(:)); K=size(desiredGrid,1);
    assert(numel(idx)==im.SampleCount&&numel(idx)==im.Plan.NumRE&& ...
        ~isempty(idx)&&all(isfinite(idx))&&all(idx==fix(idx))&& ...
        all(idx>=1&idx<=K*size(desiredGrid,2)),id,'Preserve exact original CSI-IM indices/count.');
    noiseSupport=[mod(idx-1,K) floor((idx-1)/K)];
    assert(isempty(intersect(support,noiseSupport,'rows')),id,'CSI-IM must not overlap NZP support.');
end
q=sixgr.phy.refsig.compareCSIRSPowerReference(residual,noiseSupport,nfft,pn,unit);
% Also retain original desired leakage on the muted resource. Do not silently
% identify the measured CSI-IM total with a leakage-subtracted reference.
leak=sixgr.phy.refsig.compareCSIRSPowerReference(desiredGrid,noiseSupport,nfft,zeros(1,nrx),unit);
total=sixgr.phy.refsig.compareCSIRSPowerReference(receivedGrid,noiseSupport,nfft,zeros(1,nrx),unit);
originalCSIIMCovariance=[];
if dedicated
    % This is deterministic producer binding, not a measurement-accuracy
    % criterion. measureCSIIM measures the uncentered second moment of the
    % ORIGINAL measurement grid. Reproduce its class-preserving conversion
    % before double accumulation, including single precision rounding.
    measurementGrid=receivedGrid;
    if string(unit)=="sqrt_mW"
        measurementGrid=measurementGrid./cast(double(nfft)*sqrt(1000),'like',measurementGrid);
    end
    flat=reshape(double(measurementGrid),[],nrx);
    samples=flat(idx,:);
    originalCSIIMCovariance=samples.'*conj(samples)/size(samples,1);
    originalCSIIMCovariance=(originalCSIIMCovariance+originalCSIIMCovariance')/2;
    originalPower=real(diag(originalCSIIMCovariance)).';
    assert(isfield(im,'Covariance')&&isfield(im,'PowerPerReceiveAntenna')&& ...
        isfield(im,'MeanPower')&&isfield(im,'Source')&& ...
        string(im.Source)=="configured_CSI_IM_received_RE_second_moment",id, ...
        'Require the original supported CSI-IM second-moment producer, not a filtered or substituted estimate.');
    assert(isnumeric(im.Covariance)&&~issparse(im.Covariance)&& ...
        isnumeric(im.PowerPerReceiveAntenna)&&isreal(im.PowerPerReceiveAntenna)&& ...
        ~issparse(im.PowerPerReceiveAntenna)&&isvector(im.PowerPerReceiveAntenna)&& ...
        realScalar(im.MeanPower),id,'Preserve original numeric CSI-IM covariance and power types.');
    sameMoment(double(im.Covariance),originalCSIIMCovariance,size(samples,1),id);
    sameMoment(double(im.PowerPerReceiveAntenna(:).'),originalPower,size(samples,1),id);
    sameMoment(double(im.MeanPower),mean(originalPower),size(samples,1),id);
    sameMoment(pn,originalPower,size(samples,1),id);
end
rawRatio=ps./pn;
linear=rawRatio;
est=measured.SignalPowerEstimation;
if isfield(est,'SignedPort3000SNRLinearPerBranch')
    value=est.SignedPort3000SNRLinearPerBranch;
    assert(isnumeric(value)&&isreal(value)&&~issparse(value)&&isvector(value)&&numel(value)==nrx, ...
        id,'Original estimator ratio must be numeric; numeric NaN/Inf retain their original meaning.');
    linear=double(est.SignedPort3000SNRLinearPerBranch(:).');
end
assert(isreal(linear)&&numel(linear)==nrx,id,'Preserve the original estimator-specific ratio.');
if isfield(est,'SignedPort3000SNRLinearPerBranch')
    logs=positiveLog(linear); % Original signed-estimate log availability rule.
else
    assert(all(linear>=0|isnan(linear)),id,'Native unsigned power ratio cannot be negative.');
    logs=10*log10(linear); % Native estimator retains exact zero as -Inf.
end
originalLogs=double(measured.CSI_SINRPerReceiveAntenna_dB(:).');
sameValues(originalLogs,logs,id,'Original log SINR does not match its retained estimator ratio.');
[reported,column]=selected(logs);
sameValues(double(measured.CSI_SINR_dB),reported,id,'Original SINR maximum differs from retained branches.');
sameValues(double(measured.ReceiveBranch1Based),column,id,'Original SINR selected branch differs.');
referenceRatio=p.ReferencePerReceiveColumn./q.ReferencePerReceiveColumn;
referenceLogs=10*log10(referenceRatio); % Exact zero signal is -Inf; 0/0 remains NaN.
[referenceReported,referenceColumn]=selected(referenceLogs);
errors=nan(1,nrx); valid=isfinite(logs)&isfinite(referenceLogs);
errors(valid)=logs(valid)-referenceLogs(valid);
selectedError=NaN; referenceAtSelected=NaN;
if isfinite(column)
    selectedError=errors(column); referenceAtSelected=referenceLogs(column);
end
reportedError=NaN;
if isfinite(reported)&&isfinite(referenceReported), reportedError=reported-referenceReported; end
out=struct('ContractVersion',"sixgr.csirs.original_sinr_arithmetic/v1", ...
    'LinearPowerUnit',p.LinearPowerUnit,'RawGridAmplitudeDivisor',p.RawGridAmplitudeDivisor, ...
    'ReceiveColumnCount',nrx,'SignalSupport0Based',support, ...
    'DisturbanceSupport0Based',noiseSupport,'DedicatedCSIIM',dedicated, ...
    'SignalRECount',size(support,1),'DisturbanceRECount',size(noiseSupport,1), ...
    'OriginalCSIIMSecondMomentVerified',dedicated, ...
    'OriginalCSIIMCovariance',originalCSIIMCovariance, ...
    'ReferenceDesiredPerReceiveColumn',p.ReferencePerReceiveColumn, ...
    'ReferenceDisturbancePerReceiveColumn',q.ReferencePerReceiveColumn, ...
    'DesiredPowerOnDisturbanceSupport',leak.ReferencePerReceiveColumn, ...
    'ReceivedPowerOnDisturbanceSupport',total.ReferencePerReceiveColumn, ...
    'CrossEnergyOnDisturbanceSupport',total.ReferencePerReceiveColumn- ...
        leak.ReferencePerReceiveColumn-q.ReferencePerReceiveColumn, ...
    'MeasuredSignedDesiredPerReceiveColumn',ps,'MeasuredDisturbancePerReceiveColumn',pn, ...
    'MeasuredPowerRatioPerReceiveColumn',rawRatio,'MeasuredEstimatorRatioPerReceiveColumn',linear, ...
    'ReferenceRatioPerReceiveColumn',referenceRatio,'MeasuredSINR_dB',logs, ...
    'ReferenceSINR_dB',referenceLogs,'ErrorPerReceiveColumn_dB',errors, ...
    'MeasuredSelectedColumn1',column,'ReferenceSelectedColumn1',referenceColumn, ...
    'MeasuredReportedSINR_dB',reported,'ReferenceReportedSINR_dB',referenceReported, ...
    'ReferenceAtMeasuredSelectedColumn_dB',referenceAtSelected, ...
    'MeasuredSelectedColumnError_dB',selectedError,'ReportedError_dB',reportedError, ...
    'ReferenceZeroSignal',p.ReferencePerReceiveColumn==0, ...
    'ReferenceZeroDisturbance',q.ReferencePerReceiveColumn==0, ...
    'ReferenceBothZero',p.ReferencePerReceiveColumn==0&q.ReferencePerReceiveColumn==0, ...
    'MeasuredNonpositiveDesired',ps<=0,'MeasuredZeroDisturbance',pn==0, ...
    'MeasuredNonpositiveEstimatorRatio',linear<=0, ...
    'OriginalSource',string(measured.Source),'OriginalDisturbanceSource',string(measured.DisturbanceSource), ...
    'OriginalSignalPowerEstimation',est,'OriginalInterferenceMeasurement',im, ...
    'ResidualDefinition',"original_composite_grid_minus_original_desired_grid_same_operator", ...
    'ReferencePlane',"caller_supplied_not_established_by_arithmetic", ...
    'IndependentOriginalSamplesProved',false,'StandardizedAccuracyQualified',false, ...
    'StatisticallyQualified',false,'HardwareQualified',false,'ReferenceUsedByReceiver',false);
% jsonencode encodes Inf/NaN as null. Exact tokens preserve their distinction.
names=["MeasuredPowerRatioPerReceiveColumn","MeasuredEstimatorRatioPerReceiveColumn", ...
    "ReferenceRatioPerReceiveColumn","MeasuredSINR_dB","ReferenceSINR_dB", ...
    "ErrorPerReceiveColumn_dB","MeasuredReportedSINR_dB","ReferenceReportedSINR_dB"];
out.NumericTokens=struct();
for name=names, out.NumericTokens.(name)=compose('%.17g',out.(name)); end
end

function y=positiveLog(x)
y=nan(size(x)); positive=x>0; y(positive)=10*log10(x(positive));
end
function [value,column]=selected(x)
[value,column]=max(x,[],'omitnan');
if isempty(value)||isnan(value), value=NaN; column=NaN; end
end
function sameValues(a,b,id,message)
assert(isequal(size(a),size(b))&&isequal(isnan(a),isnan(b))&& ...
    isequal(isinf(a),isinf(b))&&all(a(isinf(b))==b(isinf(b))),id,'%s',message);
finite=isfinite(b);
assert(all(abs(a(finite)-b(finite))<=64*eps(max(1,abs(b(finite))))),id,'%s',message);
end
function sameMoment(a,b,count,id)
% Roundoff bound on the original accumulation, not a physical dB threshold.
scale=max(realmin('double'),max(abs(b),[],'all'));
tolerance=64*max(1,count)*eps(scale);
assert(isequal(size(a),size(b))&&all(isfinite(a),'all')&& ...
    all(abs(a-b)<=tolerance,'all'),id, ...
    'CSI-IM operands differ from the original same-plane received second moment.');
end
function tf=realScalar(x)
tf=isnumeric(x)&&isreal(x)&&isscalar(x)&&~issparse(x);
end
function tf=booleanScalar(x)
tf=(islogical(x)||isnumeric(x))&&isreal(x)&&isscalar(x)&&~issparse(x)&& ...
    isfinite(x)&&(x==0||x==1);
end
