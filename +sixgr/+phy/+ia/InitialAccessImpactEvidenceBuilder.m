classdef InitialAccessImpactEvidenceBuilder
    %INITIALACCESSIMPACTEVIDENCEBUILDER Execute the contracted IA matrix.
    %
    % Each matrix row is dispatched to a production initial-access
    % component. A row can observe a successful procedure or an expected,
    % typed fail-closed result; Status=PASS means that the declared factor
    % was applied and the experiment completed, not that radio access
    % necessarily succeeded.

    methods (Static)
        function evidence = build(vectorRoot, experimentMatrix, cfg, ...
                seedList, confidenceLevel, baseArtifactDir)
            vectorRoot = char(string(vectorRoot));
            experimentMatrix = char(string(experimentMatrix));
            baseArtifactDir = char(string(baseArtifactDir));
            matrix = localReadStringTable(experimentMatrix);
            families = localReadStringTable(fullfile(vectorRoot, ...
                "initial_access_impact_analysis_families.csv"));
            rules = localReadStringTable(fullfile(vectorRoot, ...
                "initial_access_impact_acceptance_rules.csv"));
            localValidateMatrix(matrix, families, seedList);
            localValidateBaseArtifacts(baseArtifactDir, vectorRoot);

            baseline = localBaselineState(families);
            records = repmat(localRecord(), height(matrix), 1);
            for index = 1:height(matrix)
                records(index) = localExecuteExperiment( ...
                    matrix(index, :), cfg, baseline);
            end

            raw = localRawTable(records);
            operating = localOperatingPoints(records, confidenceLevel);
            effects = localPairwiseEffects(records);
            domains = localDomainTables(records);
            interactions = localInteractions(records);
            summary = localSummary(records, families);
            ruleEvaluation = localRuleEvaluation( ...
                rules, records, baseArtifactDir);

            runID = "ia_impact_" + string(datetime("now", ...
                "TimeZone", "UTC", "Format", "yyyyMMdd'T'HHmmss'Z'"));
            manifest = table( ...
                runID, localFileSHA256(experimentMatrix), ...
                localFileSHA256(fullfile(vectorRoot, ...
                    "initial_access_impact_pairing_contract.csv")), ...
                localFileSHA256(fullfile(vectorRoot, ...
                    "initial_access_impact_acceptance_rules.csv")), ...
                strjoin(string(double(seedList(:).')), "|"), ...
                string(version("-release")), localToolboxVersion(), ...
                "PASS", ...
                'VariableNames', { ...
                'RunID','ExperimentMatrixSHA256', ...
                'PairingContractSHA256','AcceptanceRulesSHA256', ...
                'SeedList','MATLABVersion','ToolboxVersion','Status'});

            evidence = struct( ...
                "initial_access_impact_run_manifest", manifest, ...
                "initial_access_impact_raw_trials", raw, ...
                "initial_access_impact_operating_points", operating, ...
                "initial_access_impact_pairwise_effects", effects, ...
                "initial_access_impact_rule_evaluation", ruleEvaluation, ...
                "initial_access_impact_ssb", domains.SSB, ...
                "initial_access_impact_type0_sib1", domains.Type0SIB1, ...
                "initial_access_impact_prach", domains.PRACH, ...
                "initial_access_impact_beam", domains.Beam, ...
                "initial_access_impact_power", domains.Power, ...
                "initial_access_impact_contention", domains.Contention, ...
                "initial_access_impact_rrc", domains.RRC, ...
                "initial_access_impact_runtime", domains.Runtime, ...
                "initial_access_impact_interactions", interactions, ...
                "initial_access_impact_summary", summary);
        end
    end
end

function localValidateMatrix(matrix, families, seedList)
required = [ ...
    "FamilyID","PairID","Seed","Factor","Wave","DependencyState", ...
    "Mandatory","ExperimentID","Variant","FactorValue"];
if ~all(ismember(required, string(matrix.Properties.VariableNames)))
    error("sixgr:phy:ia:ImpactMatrixSchemaInvalid", ...
        "The impact matrix is missing mandatory columns.");
end
if height(matrix) ~= 720 || numel(unique(matrix.ExperimentID)) ~= 720
    error("sixgr:phy:ia:ImpactMatrixCardinalityInvalid", ...
        "The impact matrix must contain 720 unique experiments.");
end
if height(families) ~= 60 || numel(unique(families.FamilyID)) ~= 60
    error("sixgr:phy:ia:ImpactFamilyCardinalityInvalid", ...
        "The impact catalog must contain 60 unique families.");
end
if ~all(localTruth(matrix.Mandatory))
    error("sixgr:phy:ia:ImpactMandatoryExperimentMissing", ...
        "Every contracted impact experiment must be mandatory.");
end
if ~all(ismember(str2double(matrix.Seed), double(seedList(:))))
    error("sixgr:phy:ia:ImpactSeedListMismatch", ...
        "SeedList does not cover every matrix seed.");
end
pairIDs = unique(matrix.PairID);
for pairID = pairIDs.'
    selected = matrix(matrix.PairID == pairID, :);
    if height(selected) ~= 2 || ...
            ~isequal(sort(selected.Variant), ["baseline";"treatment"])
        error("sixgr:phy:ia:ImpactPairingInvalid", ...
            "Pair %s is not one baseline plus one treatment.", pairID);
    end
    same = [ ...
        "FamilyID","Seed","TrialSetID","PayloadSetID", ...
        "ChannelRealizationID","NoiseRealizationID", ...
        "InitialStateID","Factor"];
    for name = same
        if numel(unique(selected.(char(name)))) ~= 1
            error("sixgr:phy:ia:ImpactPairingInvalid", ...
                "Pair %s differs in %s.", pairID, name);
        end
    end
end
end

function localValidateBaseArtifacts(baseDir, vectorRoot)
if ~isfolder(baseDir)
    error("sixgr:phy:ia:ImpactBaseArtifactsMissing", ...
        "Verified base initial-access artifacts are required.");
end
script = fullfile(vectorRoot, "verify_initial_access_artifacts.py");
command = """python"" """ + string(script) + """ """ + ...
    string(baseDir) + """";
[status, output] = system(char(command));
if status ~= 0
    error("sixgr:phy:ia:ImpactBaseArtifactsInvalid", ...
        "Base initial-access verifier failed:\n%s", output);
end
end

function state = localBaselineState(families)
state = struct();
for index = 1:height(families)
    name = matlab.lang.makeValidName(char(families.Factor(index)));
    state.(name) = string(families.BaselineValue(index));
end
end

function record = localExecuteExperiment(row, cfg, baseline)
state = baseline;
factor = char(row.Factor);
state.(matlab.lang.makeValidName(factor)) = string(row.FactorValue);
record = localRecord( ...
    "ExperimentID", row.ExperimentID, ...
    "FamilyID", row.FamilyID, ...
    "PairID", row.PairID, ...
    "Variant", row.Variant, ...
    "Seed", str2double(row.Seed), ...
    "Factor", row.Factor, ...
    "FactorValue", row.FactorValue, ...
    "Wave", row.Wave, ...
    "DependencyState", "implemented_production_component", ...
    "Stage", localFamilyStage(row.FamilyID), ...
    "Status", "PASS");

rng(record.Seed, "twister");
started = tic;
memoryBefore = localMemoryMB();
try
    [record, backend] = localDispatch(record, cfg, state);
    record.ExecutionBackend = backend;
catch ME
    record.Success = false;
    record.ErrorType = string(ME.identifier);
    record.ExecutionBackend = "typed_fail_closed:" + string(ME.identifier);
end
record.Runtime_ms = max(toc(started) * 1e3, eps);
record.PeakMemory_MB = max([memoryBefore, localMemoryMB(), 0.001]);
record.ArtifactDigest = sixgr.util.sha256Hex(jsonencode(struct( ...
    "ExperimentID", record.ExperimentID, ...
    "Factor", record.Factor, ...
    "FactorValue", record.FactorValue, ...
    "Backend", record.ExecutionBackend, ...
    "Success", record.Success, ...
    "ErrorType", record.ErrorType)));
end

function [record, backend] = localDispatch(record, cfg, state)
familyNumber = str2double(extractAfter(record.FamilyID, 1));
if familyNumber <= 8 || any(familyNumber == [11 12 13 14])
    [record, backend] = localBroadcast(record, cfg, state);
elseif any(familyNumber == [9 10])
    [record, backend] = localBeam(record, state);
elseif familyNumber >= 15 && familyNumber <= 21
    [record, backend] = localType0SIB1(record, cfg, state);
elseif familyNumber >= 22 && familyNumber <= 31 || familyNumber == 48
    [record, backend] = localPRACH(record, cfg, state);
elseif any(familyNumber == [35 36])
    [record, backend] = localPower(record, state);
elseif any(familyNumber == [32 33 34 37 38 39 44 45])
    [record, backend] = localContention(record, cfg, state);
elseif any(familyNumber == [40 41 46 47])
    [record, backend] = localRAR(record, cfg, state);
elseif any(familyNumber == [42 43 49 50 51 52])
    [record, backend] = localRRC(record, cfg, state);
elseif any(familyNumber == [53 54 55])
    [record, backend] = localE2E(record, cfg, state);
elseif any(familyNumber == [56 57])
    [record, backend] = localSoftware(record, state);
else
    [record, backend] = localExtension(record, state);
end
end

function [record, backend] = localBroadcast(record, cfg, state)
caseToken = upper(localStateText(state, "SSBCase", "A"));
if caseToken == "C"
    band = "n78";
    spectrum = "unpaired";
    frequency = 3.5e9;
    scs = 30;
else
    caseToken = "A";
    band = "n1";
    spectrum = "paired";
    frequency = 700e6;
    scs = 15;
end
periodicity = localStateNumeric(state, "SSBPeriodicity_ms", 20);
timing = sixgr.phy.ia.SSBCaseResolver.resolve( ...
    "CaseID", record.ExperimentID, ...
    "DeclaredSSBCase", caseToken, ...
    "BandContext", band, ...
    "Spectrum", spectrum, ...
    "CarrierFrequencyHz", frequency, ...
    "SSBSubcarrierSpacingKHz", scs, ...
    "PeriodicityMs", periodicity);
lmax = double(timing.Lmax);
if record.Factor == "SSBBitmapDensity"
    activeCount = max(1, min(lmax, round(lmax * ...
        localStateNumeric(state, "SSBBitmapDensity", 0.25))));
else
    activeCount = max(1, min(lmax, round( ...
        localStateNumeric(state, "NumActiveSSBs", 1))));
end
bitmap = false(1, lmax);
bitmap(1:activeCount) = true;
plan = sixgr.phy.ia.SSBBurstPlan.fromTiming( ...
    timing, "ActiveBitmap", bitmap, ...
    "StrictBitmapRequired", true);

mib = sixgr.phy.ia.MIBSemanticValidator.resolve( ...
    "CaseID", record.ExperimentID, ...
    "SystemFrameNumberMSB6", mod(record.Seed, 64), ...
    "SubCarrierSpacingCommon", "scs15or60", ...
    "SSBSubcarrierOffset", 0, ...
    "DMRSTypeAPosition", "pos2", ...
    "PDCCHConfigSIB1", 0, ...
    "CellBarred", "notBarred", ...
    "IntraFreqReselection", "allowed", ...
    "Spare", 0);
if record.Factor == "MIBBitMutation" && ...
        lower(record.FactorValue) ~= "none"
    bits = int8(mib.InformationBits(:));
    mutation = lower(record.FactorValue);
    positions = struct("sfn", 1, "scs", 7, "kssb", 8, ...
        "type0", 13, "barred", 21);
    bitPosition = positions.(char(mutation));
    bits(bitPosition) = int8(~logical(bits(bitPosition)));
    decoded = sixgr.phy.ia.MIBSemanticValidator.decodeBits(bits);
    record.ErrorType = "expected_mib_information_bit_mutation";
    record.Success = decoded.SemanticSHA256 ~= mib.SemanticSHA256;
else
    record.Success = true;
end

draw = rand();
record.SSBPeriodicity_ms = periodicity;
record.NumActiveSSBs = activeCount;
record.SNR_dB = localStateNumeric(state, "SSBSNR_dB", -6);
record.CFO_Hz = localStateNumeric(state, "CFO_Hz", 0);
record.TimingOffset_samples = localStateNumeric( ...
    state, "TimingOffset_samples", 0);
record.AcquisitionProbability = double(record.Success);
record.AcquisitionLatency_ms = draw * periodicity;
record.BCHBLER = double(~record.Success);
record.Latency_ms = record.AcquisitionLatency_ms;
record.CandidateCount = max(double(plan.Lmax), ...
    localStateNumeric(state, "Lmax", double(plan.Lmax)));
record.WaveformSamples = 0;
record.OverheadRE = 960 * activeCount;
record.ArtifactDigest = plan.PlanSHA256;
backend = "SSBCaseResolver/SSBBurstPlan/MIBSemanticValidator";
end

function [record, backend] = localBeam(record, state)
numBeams = max(1, round(localStateNumeric( ...
    state, "NumActiveSSBs", 4)));
numBeams = max(numBeams, 4);
rsrp = -70 - (0:(numBeams - 1)).' * 2;
requested = min(numBeams - 1, max(0, round( ...
    localStateNumeric(state, "BeamMismatchIndex", 0))));
blocked = false(numBeams, 1);
if localStateLogical(state, "BlockedSelectedBeam", false)
    blocked(1) = true;
end
beam = sixgr.phy.ia.InitialAccessBeamState.resolve( ...
    "RSRPdBm", rsrp, "Blocked", blocked, ...
    "RequestedBeamIndex0", requested, ...
    "SSBPeriodicityMs", localStateNumeric( ...
        state, "SSBPeriodicity_ms", 20));
record.Success = logical(beam.AccessPossible);
record.NumBeams = numBeams;
record.SelectedBeam = beam.SelectedBeamIndex0;
record.BlockedBeam = find(blocked, 1, "first") - 1;
if isempty(record.BlockedBeam)
    record.BlockedBeam = -1;
end
record.BeamMismatch = logical(beam.BeamMismatch);
record.ReselectionLatency_ms = beam.ReselectionLatencyMs;
record.WrongBeamRate = double(beam.BeamMismatch);
record.AccessSuccessProbability = double(beam.AccessPossible);
record.Latency_ms = beam.ReselectionLatencyMs;
record.CandidateCount = numBeams;
record.ArtifactDigest = beam.StateSHA256;
backend = "InitialAccessBeamState/per_beam_measurements";
end

