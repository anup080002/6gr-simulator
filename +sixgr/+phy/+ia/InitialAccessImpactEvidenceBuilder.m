    "PeriodicityMs", localStateNumeric( ...
        state, "SIB1Periodicity_ms", 160), ...
    "WindowLengthMs", 20, ...
    "ObservationStartMs", mod(record.Seed, 20), ...
    "Repetitions", 4);
