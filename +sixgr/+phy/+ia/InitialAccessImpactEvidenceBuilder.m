aggregation = round(localStateNumeric(state, "AggregationLevel", 4));
context = struct( ...
    "FrequencyRange", "FR1", ...
    "SSBSCSKHz", 30, ...
    "PDCCHSCSKHz", 30, ...
    "ChannelBandwidthMHz", 100, ...
    "SharedSpectrum", false, ...
    "KSSB", 0, ...
    "CORESET0Index", coresetIndex, ...
    "SearchSpaceZero", searchIndex, ...
    "SSBIndex", 0, ...
    "InitialDLBWPStart", 0, ...
    "InitialDLBWPSize", 275, ...
    "NCellID", double(sixgr.util.structGet( ...
        cfg, "phy.carrier.NCellID", 1)), ...
    "Note17Band", false, ...
    "SSBFrameNumber", 0, ...
    "ConfigurationEpoch", 1);
