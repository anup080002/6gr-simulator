function [record, backend] = localContention(record, cfg, state)
numUE = max(1, round(localStateNumeric( ...
    state, "NumContendingUEs", 1)));
pool = max(1, round(localStateNumeric( ...
    state, "CBPreamblesPerSSB", 64)));
backoff = localStateNumeric(state, "BackoffIndicator_ms", 0);
nearFar = localStateNumeric(state, "NearFarCapture_dB", 0);
maxAttempts = max(1, round(localStateNumeric( ...
    state, "PreambleTransMax", 10)));
responseWindow = max(1, round(localStateNumeric( ...
    state, "RAResponseWindow_slots", 8)));
timer = max(1, round(localStateNumeric( ...
    state, "ContentionResolutionTimer_ms", 64)));

preambles = randi(pool, numUE, 1);
counts = accumarray(preambles, 1, [pool 1]);
colliding = sum(counts(preambles) > 1);
collision = colliding / numUE;
capture = double(nearFar >= 6 && colliding > 0);
attempts = min(maxAttempts, 1 + round(collision * maxAttempts));
cfg.random_access.ra_response_window_slots=responseWindow;
cfg.random_access.ra_contention_resolution_timer_slots=timer/(1000*sixgr.time.slotDurationSec(cfg));
ra = sixgr.mac.ra.RAConfig(cfg, ...
    "RunId", record.ExperimentID, "UEId", 1);
timing = sixgr.phy.ia.RATimingService.fromRAPlan(ra, ...
    "BackoffIndicatorMs", backoff, "UniformDraw0to1", rand());
record.Success = logical(timing.RARInsideWindow) && ...
    logical(timing.ContentionResolved);
record.NumUEs = numUE;
record.PreamblePool = pool;
record.Backoff_ms = backoff;
record.NearFar_dB = nearFar;
record.CollisionProbability = collision;
record.CaptureProbability = capture;
record.MeanAttempts = attempts;
record.P95Latency_ms = attempts * ...
    (double(ra.SetupCompleteSlot) + timing.BackoffSlots + 1)*1000*sixgr.time.slotDurationSec(cfg);
record.Latency_ms = record.P95Latency_ms;
record.Energy_mJ = attempts * 1e-3;
record.ArtifactDigest = timing.ResolutionSHA256;
backend = "RATimingService/RAConfig/seeded_contention_event_process";
end

function [record, backend] = localRAR(record, cfg, state)
ra = sixgr.mac.ra.RAConfig(cfg, ...
    "RunId", record.ExperimentID, "UEId", 1);
mcs = round(localStateNumeric(state, "RARPDSCHMCS", 0));
grant = sixgr.mac.ra.buildRARULGrant(ra, ...
    "MCS", min(31, max(0, mcs)));
rapidMutation = lower(localStateText(state, "RAPIDMutation", "none"));
rntiMutation = lower(localStateText(state, "RARNTIMutation", "none"));
expectedRNTI = sixgr.phy.ra.computeRARNTI( ...
    "SymbolIndex", ra.PRACHOccasionSymbol, ...
    "SlotIndex", ra.PRACHOccasionSlot, ...
    "FrequencyIndex", ra.PRACHFrequencyIndex, ...
    "ULCarrierId", 0);
decodedRNTI = expectedRNTI;
if rntiMutation ~= "none"
    decodedRNTI = expectedRNTI + 1;
end
accepted = rapidMutation == "none" && decodedRNTI == expectedRNTI;
record.Success = logical(accepted);
if ~accepted
    record.ErrorType = "sixgr:phy:ia:RARIdentityMismatch";
end
record.PDCCHDetectionProbability = double(accepted);
record.SIB1BLER = double(~accepted);
record.Latency_ms = double(ra.Msg2Slot - ra.PRACHOccasionSlot);
record.OverheadRE = double(grant.NumPRB * grant.NumSymbols * 12);
record.CandidateCount = 1;
record.ArtifactDigest = sixgr.util.sha256Hex( ...
    jsonencode(struct("RARNTI", expectedRNTI, ...
    "Grant", grant.BitVector)));
backend = "RAConfig/buildRARULGrant/RA-RNTI_identity_gate";
end

function [record, backend] = localRRC(record, cfg, state)
requestBits = round(localStateNumeric( ...
    state, "RRCSetupRequestBits", 56));
setupBits = round(localStateNumeric(state, "RRCSetupBits", 256));
mutation = lower(localStateText( ...
    state, "TransactionMutation", "none"));
ueIdentity = "UE-" + string(record.Seed);
msg3 = sixgr.mac.ra.buildMsg3Payload( ...
    "UEId", record.Seed, ...
    "UEIdentity", ueIdentity, ...
    "RRCSetupRequest", true);
msg4 = sixgr.mac.ra.buildMsg4ContentionResolution( ...
    msg3.ContentionResolutionIdentity, ...
