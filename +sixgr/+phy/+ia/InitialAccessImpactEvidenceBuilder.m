function [lower, upper] = localWilson(successes, trials, confidence)
z = -sqrt(2) * erfcinv(2 * (0.5 + confidence / 2));
p = successes / trials;
denominator = 1 + z^2 / trials;
center = (p + z^2 / (2 * trials)) / denominator;
half = z / denominator * sqrt( ...
    p * (1 - p) / trials + z^2 / (4 * trials^2));
lower = max(0, center - half);
upper = min(1, center + half);
end

