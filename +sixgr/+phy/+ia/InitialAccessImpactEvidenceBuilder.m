function [record, backend] = localExtension(record, state)
procedure = lower(localStateText( ...
    state, "RequestedProcedure", "four_step"));
args = {"Procedure", "four_step_contention_based"};
expectedError = "";
switch procedure
    case {"four_step","four_step_contention_based"}
        % Supported baseline.
    case "two_step"
        args = [args, {"TwoStepRA", true}]; %#ok<AGROW>
        expectedError = "sixgr:phy:ia:UnsupportedTwoStepRA";
    case "cfra"
        args = [args, {"CFRA", true}]; %#ok<AGROW>
        expectedError = "sixgr:phy:ia:UnsupportedCFRA";
    case "bfr"
        args = [args, {"BFR", true}]; %#ok<AGROW>
        expectedError = "sixgr:phy:ia:UnsupportedBFR";
    case "sul"
        args = [args, {"SUL", true}]; %#ok<AGROW>
        expectedError = "sixgr:phy:ia:UnsupportedSUL";
    case "ntn"
        args = [args, {"NTN", true}]; %#ok<AGROW>
        expectedError = "sixgr:phy:ia:UnsupportedNTNAccess";
    case {"redcap","eredcap"}
        args = [args, {"RedCap", true}]; %#ok<AGROW>
        expectedError = "sixgr:phy:ia:UnsupportedRedCapAccess";
    otherwise
        error("sixgr:phy:ia:UnsupportedProfile", ...
            "Unknown requested extension %s.", procedure);
end
if strlength(expectedError) == 0
    plan = sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve(args{:});
    record.Success = logical(plan.Executable);
    record.ArtifactDigest = sixgr.util.sha256Hex(jsonencode(plan));
else
    try
        sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve(args{:});
        error("sixgr:phy:ia:ExtensionGateDidNotReject", ...
            "Unsupported extension %s did not fail closed.", procedure);
    catch ME
        if string(ME.identifier) ~= expectedError
            rethrow(ME);
        end
        record.Success = true;
        record.ErrorType = expectedError;
        record.ArtifactDigest = sixgr.util.sha256Hex( ...
            procedure + "|" + expectedError);
    end
end
record.Latency_ms = 0;
backend = "InitialAccessCapabilityRegistry_typed_gate";
end

