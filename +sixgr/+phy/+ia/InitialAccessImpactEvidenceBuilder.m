record.SIB1MCS = mcs;
record.SIB1PayloadBits = payloadBits;
record.PDCCHDetectionProbability = double(record.Success);
record.SIB1BLER = double(~record.Success);
record.Latency_ms = schedule.NextMonitoringLatencyMs;
record.OverheadRE = double(type0.CORESET0.NumRB * ...
    type0.CORESET0.DurationSymbols + requiredPRB * 12 * 10);
record.CandidateCount = height(type0.Candidates);
record.ArtifactDigest = schedule.ScheduleSHA256;
backend = "Type0PDCCHResolver/SIB1Schedule/TS38331_semantic_validator";
end

function [record, backend] = localPRACH(record, cfg, state)
format = upper(localStateText(state, "PreambleFormat", "0"));
restricted = localStateText(state, ...
    "RestrictedSet", "UnrestrictedSet");
zcz = round(localStateNumeric(state, "ZeroCorrelationZoneConfig", 0));
msg1FDM = round(localStateNumeric(state, "Msg1FDM", 1));
requestedSCS = localStateNumeric(state, "PRACHSCS_kHz", 1.25);
configurationIndex = localPRACHIndexForFormat(format);
if record.Factor == "PRACHSCS_kHz"
    [format, configurationIndex] = localFormatForSCS(requestedSCS);
end
if any(string(restricted) == ...
        ["RestrictedSetTypeA","RestrictedSetTypeB"])
    format = "0";
    configurationIndex = 16;
    requestedSCS = 1.25;
end

prachCfg = sixgr.rach.PRACHConfig(cfg, ...
    "FrequencyRange", "FR1", ...
    "DuplexMode", "FDD", ...
    "CarrierFrequencyHz", 700e6, ...
    "CarrierSCSkHz", 15, ...
    "NSizeGrid", 52, ...
    "PRACHConfigurationIndex", configurationIndex, ...
    "PRACHFormat", format, ...
    "PRACHSubcarrierSpacing", requestedSCS, ...
    "SequenceIndex", 0, ...
    "PreambleIndex", 7, ...
    "RestrictedSet", restricted, ...
    "ZeroCorrelationZone", zcz, ...
    "Msg1FDM", msg1FDM, ...
    "ChannelModel", "AWGN", ...
    "Seed", record.Seed);
occasion = sixgr.rach.mapPRACHToOccasion( ...
    prachCfg, "OccasionIndex", 1);
tx = sixgr.rach.generatePRACHWaveform( ...
    prachCfg, "Occasion", occasion, "PreambleIndex", 7);
signalPresent = localStateLogical(state, "PRACHSignalPresent", true);
if signalPresent
    rxWaveform = tx.Waveform;
else
    rxWaveform = zeros(size(tx.Waveform), "like", tx.Waveform);
end
det = sixgr.rach.PRACHDetector(rxWaveform, prachCfg, ...
    "Occasion", occasion, ...
    "CandidatePreambles", 0:63, ...
    "DetectorBackend", "toolbox_peak", ...
    "DetectionThresholdMode", "fixed", ...
    "DetectionThreshold", 0.02);
if signalPresent
    record.Success = logical(det.Detected) && ...
        double(det.DetectedPreambleIndex) == 7;
else
    record.Success = ~logical(det.Detected);
end
record.PreambleFormat = format;
record.RestrictedSet = restricted;
record.ZCZ = zcz;
record.Msg1FDM = msg1FDM;
record.RODensity = localStateNumeric( ...
    state, "RAOccasionsPer10ms", 1);
record.DetectionProbability = double( ...
    signalPresent && logical(det.Detected));
record.FalseAlarmProbability = double( ...
    ~signalPresent && logical(det.Detected));
record.TimingRMSE_samples = abs(double( ...
    sixgr.util.structGet(det, "TimingOffsetSamples", 0)));
record.CollisionProbability = 0;
record.Latency_ms = 10 / max(record.RODensity, 1);
record.CandidateCount = double(det.CandidateCount);
record.WaveformSamples = size(tx.Waveform, 1);
record.Energy_mJ = localNormalizedWaveformEnergy( ...
    tx.Waveform, tx.SampleRate_Hz);
record.ArtifactDigest = localNumericSHA(tx.Waveform);
backend = "PRACHConfig/generatePRACHWaveform/nrPRACHDetect";
end

