function summary = runInitialAccessImpactAnalysis(varargin)
%RUNINITIALACCESSIMPACTANALYSIS Execute all contracted IA impact pairs.

ip = inputParser;
ip.FunctionName = "sixgr.phy.ia.runInitialAccessImpactAnalysis";
ip.addParameter("ExperimentMatrix", fullfile(pwd, "tests", ...
    "vectors", "initial_access", ...
    "initial_access_impact_experiment_matrix.csv"), ...
    @(x)ischar(x) || (isstring(x) && isscalar(x)));
ip.addParameter("OutputDir", ...
    fullfile(pwd, "artifacts", "initial_access_impact"), ...
    @(x)ischar(x) || (isstring(x) && isscalar(x)));
ip.addParameter("BaseArtifactDir", ...
    fullfile(pwd, "artifacts", "initial_access_phase"), ...
    @(x)ischar(x) || (isstring(x) && isscalar(x)));
ip.addParameter("SeedList", [11 23 47 89 131 197], ...
    @(x)isnumeric(x) && isvector(x) && ~isempty(x));
ip.addParameter("ConfidenceLevel", 0.95, ...
    @(x)isnumeric(x) && isscalar(x) && isfinite(x) && x > 0 && x < 1);
ip.addParameter("Strict", true, ...
    @(x)islogical(x) && isscalar(x));
ip.parse(varargin{:});
opt = ip.Results;

matrixPath = char(string(opt.ExperimentMatrix));
outputDir = char(string(opt.OutputDir));
baseDir = char(string(opt.BaseArtifactDir));
seedList = double(opt.SeedList(:).');
if ~isfile(matrixPath)
    error("sixgr:phy:ia:ImpactMatrixMissing", ...
        "ExperimentMatrix does not exist.");
end
if isfile(outputDir) || isfolder(outputDir)
    error("sixgr:phy:ia:ImpactOutputAlreadyExists", ...
        "OutputDir must not exist; publication is transactional.");
end
if logical(opt.Strict) ~= true
    error("sixgr:phy:ia:StrictExecutionRequired", ...
        "Initial-access impact analysis requires Strict=true.");
end
if any(~isfinite(seedList) | seedList ~= fix(seedList))
    error("sixgr:phy:ia:ImpactSeedListInvalid", ...
        "SeedList must contain finite integers.");
end

started = tic;
setup6GRSimToolkit("Verbose", false);
repoRoot = localRepositoryRoot();
vectorRoot = fileparts(matrixPath);

testResult = runtests(fullfile(repoRoot, "tests", ...
    "testInitialAccessImpactAnalysis.m"));
if isempty(testResult) || any([testResult.Failed]) || ...
        any([testResult.Incomplete]) || ~all([testResult.Passed])
    error("sixgr:phy:ia:ImpactFocusedTestFailure", ...
        "testInitialAccessImpactAnalysis did not pass completely.");
end
testSummary = table( ...
    "testInitialAccessImpactAnalysis", numel(testResult), ...
    nnz([testResult.Passed]), nnz([testResult.Failed]), ...
    nnz([testResult.Incomplete]), sum([testResult.Duration]), ...
    'VariableNames', { ...
    'TestSuite','TestsRun','Passed','Failed','Incomplete','Duration_s'});

scenarioPath = fullfile(repoRoot, "configs", "lls", ...
    "lls_ra_four_step_strict_mini_anchor.yaml");
scenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scenario, tempdir);

parentDir = fileparts(outputDir);
if isempty(parentDir)
    parentDir = pwd;
end
if ~isfolder(parentDir)
    [ok, message] = mkdir(parentDir);
    if ~ok
        error("sixgr:phy:ia:ImpactOutputParentCreateFailed", "%s", message);
    end
end
stageDir = tempname(parentDir);
[ok, message] = mkdir(stageDir);
if ~ok
    error("sixgr:phy:ia:ImpactStageCreateFailed", "%s", message);
end
cleanup = onCleanup(@() localRemoveStage(stageDir));

evidence = sixgr.phy.ia.InitialAccessImpactEvidenceBuilder.build( ...
    vectorRoot, matrixPath, cfg, seedList, ...
    double(opt.ConfidenceLevel), baseDir);
exported = sixgr.phy.ia.InitialAccessArtifactExporter.exportImpact( ...
    evidence, stageDir, vectorRoot);
if exported.CSVCount ~= 16 || exported.PNGCount ~= 30
    error("sixgr:phy:ia:ImpactArtifactCountMismatch", ...
        "Impact output is %d CSV/%d PNG; expected 16/30.", ...
        exported.CSVCount, exported.PNGCount);
end

[verifierStatus, verifierOutput, verifierCommand] = localRunPython( ...
    fullfile(vectorRoot, ...
    "verify_initial_access_impact_artifacts.py"), stageDir);
if verifierStatus ~= 0
    error("sixgr:phy:ia:ImpactArtifactVerificationFailed", ...
        "Initial-access impact verifier failed:\n%s", verifierOutput);
end

inventory = localInventory(stageDir, exported);
[moved, moveMessage] = movefile(stageDir, outputDir);
if ~moved
    error("sixgr:phy:ia:ImpactPublishFailed", ...
        "Unable to publish impact artifacts: %s", moveMessage);
end
clear cleanup

raw = evidence.initial_access_impact_raw_trials;
rules = evidence.initial_access_impact_rule_evaluation;
summary = struct( ...
    "ContractVersion", "InitialAccessImpactAnalysis/v1", ...
    "Passed", true, ...
    "ExperimentMatrix", string(matrixPath), ...
    "BaseArtifactDir", string(baseDir), ...
    "OutputDir", string(outputDir), ...
    "ScenarioPath", string(scenarioPath), ...
    "SeedList", seedList, ...
    "ConfidenceLevel", double(opt.ConfidenceLevel), ...
    "Strict", true, ...
    "MATLABRelease", string(version("-release")), ...
    "TestSummary", testSummary, ...
    "ExperimentsExecuted", height(raw), ...
    "FamiliesExecuted", numel(unique(raw.FamilyID)), ...
    "AcceptanceRulesEvaluated", height(rules), ...
    "ContractedCSVCount", exported.CSVCount, ...
    "ContractedPNGCount", exported.PNGCount, ...
    "CSVFiles", exported.CSVFiles, ...
    "CSVRowCounts", exported.CSVRowCounts, ...
    "PNGFiles", exported.PNGFiles, ...
    "ArtifactVerifierCommand", string(verifierCommand), ...
    "ArtifactVerifierExitCode", verifierStatus, ...
    "ArtifactVerifierOutput", string(strtrim(verifierOutput)), ...
    "ArtifactInventory", inventory, ...
    "DurationSeconds", toc(started));
end

function root = localRepositoryRoot()
root = fileparts(mfilename("fullpath"));
for index = 1:3
    root = fileparts(root);
end
if ~isfile(fullfile(root, "setup6GRSimToolkit.m"))
    error("sixgr:phy:ia:RepositoryRootNotFound", ...
        "Unable to locate the simulator repository root.");
end
end

function [status, output, command] = localRunPython(script, argument)
command = """python"" """ + string(script) + """ """ + ...
    string(argument) + """";
[status, output] = system(char(command));
end

function inventory = localInventory(stageDir, exported)
names = [exported.CSVFiles(:); exported.PNGFiles(:)];
kind = [repmat("CSV", numel(exported.CSVFiles), 1); ...
    repmat("PNG", numel(exported.PNGFiles), 1)];
bytes = zeros(numel(names), 1);
hash = strings(numel(names), 1);
width = nan(numel(names), 1);
height = nan(numel(names), 1);
for index = 1:numel(names)
    path = fullfile(stageDir, names(index));
    metadata = dir(path);
    bytes(index) = metadata.bytes;
    hash(index) = localFileSHA256(path);
    if kind(index) == "PNG"
        image = imfinfo(path);
        width(index) = image.Width;
        height(index) = image.Height;
    end
end
inventory = table(names, kind, bytes, hash, width, height, ...
    repmat("PASS", numel(names), 1), ...
    'VariableNames', {'FileName','Kind','Bytes','SHA256', ...
    'Width','Height','Status'});
end

function hash = localFileSHA256(path)
fid = fopen(path, "rb");
if fid < 0
    error("sixgr:phy:ia:ImpactArtifactReadFailed", ...
        "Unable to read %s.", path);
end
cleanup = onCleanup(@() fclose(fid));
hash = string(sixgr.util.sha256Hex(fread(fid, Inf, "*uint8")));
clear cleanup
end

function localRemoveStage(path)
if isfolder(path)
    rmdir(path, "s");
end
end
