classdef RAPowerController
    %RAPOWERCONTROLLER Exact Msg1 open-loop/ramping power resolution.

    methods (Static)
        function delta = deltaPreamble(format, msg1SCSkHz)
            % TS 38.321 7.3 Tables 7.3-1/2. These normative constants
            % depend on the executed preamble format and PRACH numerology,
            % not on the data carrier or a scenario-specific default.
            format=upper(string(format));
            if ~isscalar(format)
                error('sixgr:phy:ia:UnknownPRACHPowerFormat','Use one materialized concrete PRACH format.');
            end
            formats=["0","1","2","3","A1","A2","A3","B1","B2","B3","B4","C0","C2"];
            base=[0 -3 -6 0 8 5 3 8 5 3 0 11 5];
            index=find(formats==format,1);
            if isempty(index)
                error('sixgr:phy:ia:UnknownPRACHPowerFormat','Use the materialized concrete PRACH format.');
            end
            delta=base(index);
            if index>4
                validateattributes(msg1SCSkHz,{'numeric'},{'real','scalar','finite','positive'});
                mu=log2(double(msg1SCSkHz)/15);
                if mu<0 || mu~=fix(mu)
                    error('sixgr:phy:ia:InvalidPRACHPowerNumerology','Short PRACH requires an exact NR numerology.');
                end
                delta=delta+3*mu;
            end
        end

        function result = resolve(varargin)
            p = inputParser;
            p.FunctionName = ...
                "sixgr.phy.ia.RAPowerController.resolve";
            addParameter(p, "PreambleReceivedTargetPowerdBm", ...
                NaN, @localFiniteScalar);
            addParameter(p, "DeltaPreambledB", 0, @localFiniteScalar);
            addParameter(p, "PowerRampingStepdB", ...
                NaN, @localNonnegativeFinite);
            addParameter(p, "PreamblePowerRampingCounter", ...
                NaN, @localPositiveInteger);
            addParameter(p, "MeasuredPathlossdB", ...
                NaN, @localNonnegativeFinite);
            addParameter(p, "PCMAXdBm", NaN, @localFiniteScalar);
            parse(p, varargin{:});
            opt = p.Results;

            target = double(opt.PreambleReceivedTargetPowerdBm) + ...
                double(opt.DeltaPreambledB) + ...
                (double(opt.PreamblePowerRampingCounter) - 1) * ...
                double(opt.PowerRampingStepdB);
            requested = target + double(opt.MeasuredPathlossdB);
            applied = min(requested, double(opt.PCMAXdBm));
            clipped = requested > double(opt.PCMAXdBm);

            payload = struct( ...
                "ContractVersion", "sixgr_ra_power_release18/v1", ...
                "Standard", "3GPP TS 38.213 V18.8.0 clause 7.4", ...
                "PreambleReceivedTargetPowerdBm", ...
                    double(opt.PreambleReceivedTargetPowerdBm), ...
                "DeltaPreambledB", double(opt.DeltaPreambledB), ...
                "PowerRampingStepdB", ...
                    double(opt.PowerRampingStepdB), ...
                "PreamblePowerRampingCounter", ...
                    double(opt.PreamblePowerRampingCounter), ...
                "MeasuredPathlossdB", ...
                    double(opt.MeasuredPathlossdB), ...
                "PCMAXdBm", double(opt.PCMAXdBm), ...
                "PreambleTargetAtGNBdBm", target, ...
                "RequestedTxPowerdBm", requested, ...
                "AppliedTxPowerdBm", applied, ...
                "PowerHeadroomdB", double(opt.PCMAXdBm) - applied, ...
                "Clipped", logical(clipped), ...
                "ProxyUsed", false, ...
                "FallbackUsed", false, ...
                "Status", "resolved");
            result = payload;
            result.ResolutionSHA256 = ...
                sixgr.util.sha256Hex(jsonencode(payload));
        end
    end
end

function tf = localFiniteScalar(value)
tf = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value);
end

function tf = localNonnegativeFinite(value)
tf = localFiniteScalar(value) && value >= 0;
end

function tf = localPositiveInteger(value)
tf = localFiniteScalar(value) && value >= 1 && value == fix(value);
end
