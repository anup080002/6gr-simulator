classdef InitialAccessCapabilityRegistry
    %INITIALACCESSCAPABILITYREGISTRY Fail-closed access capability planner.

    methods (Static)
        function plan = resolve(varargin)
            p = inputParser;
            p.FunctionName = ...
                "sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve";
            addParameter(p, "Profile", ...
                "fr1_four_step_ra_rrc_connection_strict_r18", ...
                @localTextScalar);
            addParameter(p, "Procedure", "four_step_contention_based", ...
                @localTextScalar);
            addParameter(p, "FrequencyRange", "FR1", @localTextScalar);
            addParameter(p, "TwoStepRA", false, @localLogicalScalar);
            addParameter(p, "CFRA", false, @localLogicalScalar);
            addParameter(p, "BFR", false, @localLogicalScalar);
            addParameter(p, "SUL", false, @localLogicalScalar);
            addParameter(p, "NTN", false, @localLogicalScalar);
            addParameter(p, "RedCap", false, @localLogicalScalar);
            addParameter(p, "ERedCap", false, @localLogicalScalar);
            parse(p, varargin{:});
            opt = p.Results;

            procedure = lower(strtrim(string(opt.Procedure)));
            localRejectProcedure(procedure, opt);
            profile = sixgr.phy.ia.InitialAccessSpecificationProfile.resolve( ...
                opt.Profile);
            range = upper(strtrim(string(opt.FrequencyRange)));
            if range ~= profile.FrequencyRange
                error("sixgr:phy:ia:UnsupportedProfile", ...
                    "Profile %s supports FR1 only, not %s.", ...
                    profile.ProfileID, range);
            end

            if procedure ~= profile.RandomAccessProcedure
                error("sixgr:phy:ia:UnsupportedProfile", ...
                    "Random-access procedure '%s' is not executable in %s.", ...
                    procedure, profile.ProfileID);
            end

            plan = struct( ...
                "Profile", profile, ...
                "Procedure", procedure, ...
                "FrequencyRange", range, ...
                "Executable", true, ...
                "WaveformGenerated", false, ...
                "StateMutationCount", 0, ...
                "FallbackCount", 0, ...
                "PlanningStatus", "SUPPORTED_STRICT", ...
                "CompletionCriterion", profile.RRCCompletionCriterion);
        end

        function plan = fromConfig(cfg)
            if ~isstruct(cfg)
                error("sixgr:phy:ia:UnsupportedProfile", ...
                    "Initial-access configuration must be a scalar struct.");
            end
            profile = sixgr.util.structGet(cfg, "initial_access.profile", ...
                "fr1_four_step_ra_rrc_connection_strict_r18");
            procedure = sixgr.util.structGet(cfg, ...
                "random_access.procedure", ...
                sixgr.util.structGet(cfg, ...
                "initial_access.random_access_procedure", ...
                "four_step_contention_based"));
            range = sixgr.util.structGet(cfg, "phy.frequencyRange", ...
                sixgr.util.structGet(cfg, "frequency.range_name", "FR1"));
            plan = sixgr.phy.ia.InitialAccessCapabilityRegistry.resolve( ...
                "Profile", profile, ...
                "Procedure", procedure, ...
                "FrequencyRange", range, ...
                "TwoStepRA", sixgr.util.structGet(cfg, ...
                    "random_access.two_step_enabled", sixgr.util.structGet( ...
                    cfg, "initial_access.extensions.two_step_ra", false)), ...
                "CFRA", sixgr.util.structGet(cfg, ...
                    "random_access.contention_free", sixgr.util.structGet( ...
                    cfg, "initial_access.extensions.contention_free_ra", false)), ...
                "BFR", sixgr.util.structGet(cfg, ...
                    "random_access.beam_failure_recovery", sixgr.util.structGet( ...
                    cfg, "initial_access.extensions.beam_failure_recovery", false)), ...
                "SUL", sixgr.util.structGet(cfg, ...
                    "random_access.supplementary_uplink", sixgr.util.structGet( ...
                    cfg, "initial_access.extensions.supplementary_uplink", false)), ...
                "NTN", sixgr.util.structGet(cfg, ...
                    "random_access.ntn", sixgr.util.structGet( ...
                    cfg, "initial_access.extensions.ntn_access", false)), ...
                "RedCap", sixgr.util.structGet(cfg, ...
                    "random_access.redcap", sixgr.util.structGet( ...
                    cfg, "initial_access.extensions.redcap_access", false)), ...
                "ERedCap", sixgr.util.structGet(cfg, ...
                    "random_access.eredcap", sixgr.util.structGet( ...
                    cfg, "initial_access.extensions.eredcap_access", false)));
        end
    end
end

function localRejectProcedure(procedure, opt)
if logical(opt.TwoStepRA) || any(procedure == ["two_step", "two_step_ra"])
    error("sixgr:phy:ia:UnsupportedTwoStepRA", ...
        "Two-step random access is not implemented in the bounded profile.");
elseif logical(opt.CFRA) || procedure == "cfra"
    error("sixgr:phy:ia:UnsupportedCFRA", ...
        "Contention-free random access is not implemented.");
elseif logical(opt.BFR) || any(procedure == ...
        ["bfr", "beam_failure_recovery"])
    error("sixgr:phy:ia:UnsupportedBFR", ...
        "Beam-failure-recovery random access is not implemented.");
elseif logical(opt.SUL) || procedure == "sul_access"
    error("sixgr:phy:ia:UnsupportedSUL", ...
        "Supplementary-uplink random access is not implemented.");
elseif logical(opt.NTN) || procedure == "ntn_access"
    error("sixgr:phy:ia:UnsupportedNTNAccess", ...
        "NTN random access is not implemented.");
elseif logical(opt.RedCap) || logical(opt.ERedCap) || ...
        any(procedure == ["redcap_access", "eredcap_access"])
    error("sixgr:phy:ia:UnsupportedRedCapAccess", ...
        "RedCap/eRedCap random access is not implemented.");
end
end

function tf = localTextScalar(value)
tf = ischar(value) || (isstring(value) && isscalar(value));
end

function tf = localLogicalScalar(value)
tf = (islogical(value) || isnumeric(value)) && isscalar(value);
end
