classdef DecodedMIBState
    %DECODEDMIBSTATE Immutable MIB state created only from CRC-valid PBCH.

    methods (Static)
        function state = create(pbchEvidence, configurationEpoch)
            if nargin < 2
                configurationEpoch = 1;
            end
            if ~isstruct(pbchEvidence) || ...
                    ~logical(sixgr.util.structGet( ...
                    pbchEvidence, "Ok", false)) || ...
                    double(sixgr.util.structGet( ...
                    pbchEvidence, "ErrFlag", 1)) ~= 0
                error("sixgr:phy:ia:PBCHCRCFailure", ...
                    "DecodedMIBState requires CRC-valid PBCH/BCH evidence.");
            end
            transportBlock = sixgr.util.structGet( ...
                pbchEvidence, "TransportBlock", []);
            if isempty(transportBlock)
                error("sixgr:phy:ia:PBCHCRCFailure", ...
                    "CRC-valid PBCH evidence is missing its transport block.");
            end
            mib = sixgr.phy.broadcast.decodeMIBTransportBlock( ...
                transportBlock);
            epoch = double(configurationEpoch);
            if ~(isscalar(epoch) && isfinite(epoch) && ...
                    epoch >= 0 && epoch == fix(epoch))
                error("sixgr:phy:ia:MIBSemanticFailure", ...
                    "ConfigurationEpoch must be a nonnegative integer.");
            end

            evidencePayload = struct( ...
                "BCHTransportBlockHash", string(sixgr.util.structGet( ...
                    pbchEvidence, "BCHTransportBlockHash", ...
                    mib.TransportBlockHash)), ...
                "NCellID", double(sixgr.util.structGet( ...
                    pbchEvidence, "NCellID", NaN)), ...
                "SSBIndex", double(sixgr.util.structGet( ...
                    pbchEvidence, "SSBIndex", NaN)), ...
                "MIBSemanticSHA256", string(mib.MIBSemanticSHA256), ...
                "ConfigurationEpoch", epoch);
            state = struct( ...
                "ContractVersion", "sixgr_decoded_mib_state/v1", ...
                "EvidenceID", sixgr.util.sha256Hex( ...
                    jsonencode(evidencePayload)), ...
                "ConfigurationEpoch", uint64(epoch), ...
                "NCellID", evidencePayload.NCellID, ...
                "SSBIndex", evidencePayload.SSBIndex, ...
                "MIBInformationBits23", mib.MIBInformationBits23, ...
                "SystemFrameNumberMSB6", mib.SystemFrameNumberMSB6, ...
                "SubCarrierSpacingCommon", mib.SubCarrierSpacingCommon, ...
                "SSBSubcarrierOffset", mib.SSBSubcarrierOffset, ...
                "DMRSTypeAPosition", mib.DMRSTypeAPosition, ...
                "PDCCHConfigSIB1", mib.PDCCHConfigSIB1, ...
                "CORESET0Index", mib.CORESET0Index, ...
                "SearchSpaceZero", mib.SearchSpaceZero, ...
                "CellBarred", mib.CellBarred, ...
                "IntraFreqReselection", mib.IntraFreqReselection, ...
                "SemanticValidationStatus", ...
                    mib.SemanticValidationStatus, ...
                "MIBSemanticSHA256", mib.MIBSemanticSHA256, ...
                "BCHTransportBlockHash", ...
                    evidencePayload.BCHTransportBlockHash, ...
                "Source", "crc_valid_nrBCHDecode_transport_block", ...
                "Immutable", true);
        end
    end
end
