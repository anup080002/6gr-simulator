classdef PRACHReferenceCatalog
    %PRACHREFERENCECATALOG Release-pinned independent TS 38.211 rows.
    %
    % The catalog is generated from the official 3GPP V18.8.0 document
    % without MATLAB/5G Toolbox. It is used as an independent conformance
    % check on Toolbox materialization, not as a fallback waveform engine.

    methods (Static)
        function row = resolveFR1(duplexMode, configurationIndex)
            duplex = upper(strtrim(string(duplexMode)));
            if any(duplex == ["FDD","SUL"])
                context = "FR1_PAIRED_SUL";
            elseif duplex == "TDD"
                context = "FR1_UNPAIRED";
            else
                error("sixgr:phy:ia:InvalidPRACHReferenceContext", ...
                    "FR1 PRACH reference duplex must be FDD, SUL, or TDD.");
            end
            index = double(configurationIndex);
            if ~(isscalar(index) && isfinite(index) && index >= 0 && ...
                    index == fix(index))
                error("sixgr:phy:ia:InvalidPRACHConfigurationIndex", ...
                    "PRACH reference index must be a nonnegative integer.");
            end
            catalog = localCatalog();
            selected = catalog.DuplexContext == context & ...
                catalog.ConfigurationIndex == index;
            if nnz(selected) ~= 1
                error("sixgr:phy:ia:InvalidPRACHConfigurationIndex", ...
                    "No unique Release-18 row exists for %s index %d.", ...
                    context, index);
            end
            t = catalog(selected, :);
            row = struct( ...
                "SourceTable", t.SourceTable(1), ...
                "ConfigurationIndex", double(t.ConfigurationIndex(1)), ...
                "PreambleFormat", t.PreambleFormat(1), ...
                "x", double(t.x(1)), ...
                "y", double(t.y(1)), ...
                "FrameOrSlotNumbers", localNumberSet( ...
                    t.FrameOrSlotNumbers(1)), ...
                "StartingSymbol", double(t.StartingSymbol(1)), ...
                "PRACHSlotsPerReferenceUnit", ...
                    double(t.PRACHSlotsPerReferenceUnit(1)), ...
                "NumTimeOccasions", ...
                    double(t.NumTimeOccasions(1)), ...
                "PRACHDuration", double(t.PRACHDuration(1)), ...
                "Reserved", localLogical(t.Reserved(1)), ...
                "SpecRelease", t.SpecRelease(1), ...
                "SourceArchiveSHA256", t.SourceArchiveSHA256(1), ...
                "SourceDocumentSHA256", t.SourceDocumentSHA256(1), ...
                "CatalogSHA256", localFileHash(localCatalogPath()), ...
                "IndependentImplementation", ...
                    "pandoc+pandas official-DOCX table extraction", ...
                "SelfConsistencyOnly", false);
        end

        function table = allFR1()
            table = localCatalog();
        end

        function report = validateAgainstToolbox()
            if isempty(which("nrPRACHConfig"))
                error("sixgr:phy:ia:PRACHToolboxDependencyMissing", ...
                    "Independent PRACH comparison requires nrPRACHConfig.");
            end
            toolbox = nrPRACHConfig.Tables;
            reference = localCatalog();
            template = struct( ...
                "DuplexContext", "", ...
                "ConfigurationIndex", NaN, ...
                "IndependentSourceTable", "", ...
                "ToolboxSourceTable", "", ...
                "MismatchCount", NaN, ...
                "CatalogSHA256", "", ...
                "SourceDocumentSHA256", "", ...
                "SelfConsistencyOnly", false, ...
                "Status", "");
            rows = repmat(template, height(reference), 1);
            for ii = 1:height(reference)
                context = reference.DuplexContext(ii);
                if context == "FR1_PAIRED_SUL"
                    tableData = toolbox.ConfigurationsFR1PairedSUL;
                    tableName = "TS_38_211_Table_6_3_3_2_2";
                else
                    tableData = toolbox.ConfigurationsFR1Unpaired;
                    tableName = "TS_38_211_Table_6_3_3_2_3";
                end
                index = double(reference.ConfigurationIndex(ii));
                selected = find( ...
                    double(tableData.ConfigurationIndex) == index);
                mismatch = 0;
                if numel(selected) ~= 1
                    mismatch = 1;
                else
                    mismatch = localToolboxMismatch( ...
                        tableData(selected, :), reference(ii, :));
                end
                rows(ii) = struct( ...
                    "DuplexContext", context, ...
                    "ConfigurationIndex", index, ...
                    "IndependentSourceTable", ...
                        reference.SourceTable(ii), ...
                    "ToolboxSourceTable", tableName, ...
                    "MismatchCount", mismatch, ...
                    "CatalogSHA256", localFileHash( ...
                        localCatalogPath()), ...
                    "SourceDocumentSHA256", ...
                        reference.SourceDocumentSHA256(ii), ...
                    "SelfConsistencyOnly", false, ...
                    "Status", string(ternary( ...
                        mismatch == 0, "PASS", "FAIL")));
            end
            report = struct2table(rows, "AsArray", true);
        end
    end
end

function value = localLogical(raw)
if islogical(raw)
    value = raw;
elseif isnumeric(raw)
    value = raw ~= 0;
else
    value = any(lower(strtrim(string(raw))) == ["true","1","yes"]);
end
end

function catalog = localCatalog()
persistent cached
if isempty(cached)
    path = localCatalogPath();
    if exist(path, "file") ~= 2
        error("sixgr:phy:ia:MissingPRACHReferenceCatalog", ...
            "Independent PRACH catalog is missing: %s", path);
    end
    options = detectImportOptions(path, ...
        "TextType", "string", "VariableNamingRule", "preserve");
    options = setvartype(options, [ ...
        "SourceTable","DuplexContext","PreambleFormat", ...
        "FrameOrSlotNumbers","SpecRelease","SourceArchiveSHA256", ...
        "SourceDocumentSHA256"], "string");
    cached = readtable(path, options);
end
catalog = cached;
end

function path = localCatalogPath()
here = fileparts(mfilename("fullpath"));
root = fileparts(fileparts(fileparts(here)));
path = fullfile(root, "tests", "vectors", "initial_access", ...
    "prach_release18_reference_catalog.csv");
end

function values = localNumberSet(text)
tokens = split(string(text), "|");
values = str2double(tokens);
values = values(isfinite(values));
end

function hash = localFileHash(path)
fid = fopen(path, "r");
if fid < 0
    hash = "";
    return;
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
hash = sixgr.rrc.asn1.sha256Hex(fread(fid, Inf, "*uint8"));
end

function count = localToolboxMismatch(actual, expected)
names = string(actual.Properties.VariableNames);
numberField = names(ismember(names, ["SubframeNumber","SlotNumber"]));
slotField = names(ismember(names, ...
    ["PRACHSlotsPerSubframe","PRACHSlotsPer60kHzSlot"]));
count = 0;
count = count + ~localTextEqual( ...
    actual.PreambleFormat, expected.PreambleFormat);
count = count + ~localNumericEqual( ...
    double(actual.x), double(expected.x));
count = count + ~localNumericEqual( ...
    double(localCellValue(actual.y)), double(expected.y));
if numel(numberField) ~= 1
    count = count + 1;
else
    actualNumbers = sort(double(localCellValue( ...
        actual.(numberField))));
    expectedNumbers = sort(localNumberSet( ...
        expected.FrameOrSlotNumbers));
    count = count + ~isequaln( ...
        actualNumbers(:), expectedNumbers(:));
end
count = count + ~localNumericEqual( ...
    double(actual.StartingSymbol), ...
    double(expected.StartingSymbol));
if numel(slotField) ~= 1
    count = count + 1;
else
    count = count + ~localNumericEqual( ...
        double(actual.(slotField)), ...
        double(expected.PRACHSlotsPerReferenceUnit));
end
count = count + ~localNumericEqual( ...
    double(actual.NumTimeOccasions), ...
    double(expected.NumTimeOccasions));
count = count + ~localNumericEqual( ...
    double(actual.PRACHDuration), ...
    double(expected.PRACHDuration));
end

function value = localCellValue(value)
if iscell(value)
    value = value{1};
end
end

function tf = localTextEqual(a, b)
tf = string(a) == string(b);
end

function tf = localNumericEqual(a, b)
tf = isequaln(double(a), double(b)) || ...
    (isscalar(a) && isscalar(b) && isfinite(a) && ...
    isfinite(b) && abs(double(a) - double(b)) < 1e-12);
end

function out = ternary(condition, a, b)
if condition
    out = a;
else
    out = b;
end
end
