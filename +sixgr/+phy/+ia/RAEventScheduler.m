classdef RAEventScheduler
    %RAEVENTSCHEDULER Event-driven slot ownership for bounded four-step RA.

    methods (Static)
        function schedule = resolve(varargin)
            p = inputParser;
            p.FunctionName = "sixgr.phy.ia.RAEventScheduler.resolve";
            addParameter(p, "PRACHOccasionEndSlot", NaN, ...
                @localNonnegativeInteger);
            addParameter(p, "RAResponseWindowSlots", NaN, ...
                @localPositiveInteger);
            addParameter(p, "RARProcessingDelaySlots", NaN, ...
                @localPositiveInteger);
            addParameter(p, "Msg3K2Slots", NaN, ...
                @localPositiveInteger);
            addParameter(p, "Msg4ProcessingDelaySlots", NaN, ...
                @localNonnegativeInteger);
            addParameter(p, "ContentionResolutionTimerSlots", NaN, ...
                @localPositiveInteger);
            addParameter(p, "SetupCompleteK2Slots", NaN, ...
                @localPositiveInteger);
            addParameter(p, "Msg3TimeDomainAllocation", struct(), @isstruct);
            addParameter(p, "FrameEngine", [], ...
                @(x)isa(x,"sixgr.phy.FrameStructureEngine"));
            addParameter(p, "Msg2SymbolAllocation", [], @localAllocation);
            addParameter(p, "Msg4SymbolAllocation", [], @localAllocation);
            addParameter(p, "SetupCompleteSymbolAllocation", [], @localAllocation);
            addParameter(p, "RequireSetupComplete", true, ...
                @(x)islogical(x) && isscalar(x));
            parse(p, varargin{:});
            opt = p.Results;
            frame = opt.FrameEngine;
            a = opt.Msg3TimeDomainAllocation;
            if ~isa(frame,"sixgr.phy.FrameStructureEngine") || ...
                    ~all(isfield(a,["K2","Msg3AdditionalDelaySlots","StartSymbol","NumSymbols"])) || ...
                    ~localNonnegativeInteger(a.K2) || ...
                    ~localNonnegativeInteger(a.Msg3AdditionalDelaySlots) || ...
                    ~localAllocation([a.StartSymbol a.NumSymbols]) || ...
                    ~localAllocation(opt.Msg2SymbolAllocation) || ...
                    ~localAllocation(opt.Msg4SymbolAllocation) || ...
                    (opt.RequireSetupComplete && ~localAllocation(opt.SetupCompleteSymbolAllocation))
                error("sixgr:phy:ia:MissingRAAllocationAuthority", ...
                    "RA planning requires canonical duplex state and actual stage time-domain allocations.");
            end
            if double(opt.Msg3K2Slots) ~= double(a.K2)
                error("sixgr:phy:ia:RARConfiguredK2Mismatch", ...
                    "random_access.timing.msg3_k2_slots=%d contradicts signalled TDRA K2=%d; delta=%d is additional.", ...
                    double(opt.Msg3K2Slots),double(a.K2),double(a.Msg3AdditionalDelaySlots));
            end

            responseStart = double(opt.PRACHOccasionEndSlot) + 1;
            responseLast = responseStart + ...
                double(opt.RAResponseWindowSlots) - 1;
            msg2 = double(opt.PRACHOccasionEndSlot) + ...
                double(opt.RARProcessingDelaySlots);
            if msg2 < responseStart || msg2 > responseLast
                error("sixgr:phy:ia:RAROutsideResponseWindow", ...
                    "Configured RAR processing delay schedules Msg2 at slot %d outside [%d,%d].", ...
                    msg2, responseStart, responseLast);
            end
            msg2Earliest = msg2;
            found = false;
            for candidate = msg2Earliest:responseLast
                msg3Candidate = candidate + double(a.K2) + double(a.Msg3AdditionalDelaySlots);
                if frame.IsDLAllocation(candidate,opt.Msg2SymbolAllocation) && ...
                        frame.IsULAllocation(msg3Candidate,[a.StartSymbol a.NumSymbols])
                    msg2 = candidate;
                    msg3 = msg3Candidate;
                    found = true;
                    break;
                end
            end
            if ~found
                error("sixgr:phy:ia:NoLegalRARMsg3Allocation", ...
                    "No Msg2 allocation in response window [%d,%d] yields legal Msg3 at K2+delta=%d.", ...
                    msg2Earliest,responseLast,double(a.K2+a.Msg3AdditionalDelaySlots));
            end
            % FDD permits simultaneous directions, but Msg4 still depends on
            % completed Msg3 reception. A zero configured processing delay
            % must not place Msg4 symbols before the last Msg3 symbol.
            earliestAfterMsg3 = msg3 + max(0,ceil( ...
                (double(a.StartSymbol+a.NumSymbols) - ...
                double(opt.Msg4SymbolAllocation(1))) / frame.SymbolsPerSlot));
            msg4 = max(msg3 + double(opt.Msg4ProcessingDelaySlots), earliestAfterMsg3);
            contentionExpiry = msg3 + ...
                double(opt.ContentionResolutionTimerSlots);
            if msg4 < msg3 || msg4 >= contentionExpiry
                error("sixgr:phy:ia:Msg4OutsideContentionWindow", ...
                    "Configured Msg4 processing schedules slot %d outside [%d,%d).", ...
                    msg4, msg3, contentionExpiry);
            end
            msg4Earliest = msg4;
            found = false;
            for candidate = msg4Earliest:(contentionExpiry-1)
                setupCandidate = candidate + double(opt.SetupCompleteK2Slots);
                if frame.IsDLAllocation(candidate,opt.Msg4SymbolAllocation) && ...
                        (~opt.RequireSetupComplete || ...
                        frame.IsULAllocation(setupCandidate,opt.SetupCompleteSymbolAllocation))
                    msg4 = candidate;
                    setupComplete = setupCandidate;
                    found = true;
                    break;
                end
            end
            if ~found
                error("sixgr:phy:ia:NoLegalMsg4SetupAllocation", ...
                    "No legal Msg4/SRB1 allocation before contention expiry %d with setup_complete_k2_slots=%d.", ...
                    contentionExpiry,double(opt.SetupCompleteK2Slots));
            end
            payload = struct( ...
                "ContractVersion", "sixgr_ra_event_schedule_r18/v2", ...
                "Source", "rar_tdra_and_canonical_duplex_allocations", ...
                "DuplexMode", frame.DuplexMode, ...
                "PRACHOccasionEndSlot", ...
                    double(opt.PRACHOccasionEndSlot), ...
                "ResponseWindowStartSlot", responseStart, ...
                "ResponseWindowLastSlot", responseLast, ...
                "RARProcessingDelaySlots", ...
                    double(opt.RARProcessingDelaySlots), ...
                "Msg2Slot", msg2, ...
                "Msg2EarliestSlot", msg2Earliest, ...
                "Msg3K2Slots", double(opt.Msg3K2Slots), ...
                "Msg3AdditionalDelaySlots", double(a.Msg3AdditionalDelaySlots), ...
                "Msg3TimeDomainAllocation", a, ...
                "Msg3Slot", msg3, ...
                "Msg4ProcessingDelaySlots", ...
                    double(opt.Msg4ProcessingDelaySlots), ...
                "Msg4Slot", msg4, ...
                "Msg4EarliestSlot", msg4Earliest, ...
                "ContentionExpirySlotExclusive", contentionExpiry, ...
                "SetupCompleteK2Slots", ...
                    double(opt.SetupCompleteK2Slots), ...
                "SetupCompleteSlot", setupComplete, ...
                "DuplexAllocationsValidated", true, ...
                "ControlMonitoringQualified", false, ...
                "SetupCompleteGrantQualified", false, ...
                "ProxyUsed", false, "FallbackUsed", false, ...
                "Status", "allocation_plan_not_control_or_causal_execution_qualification");
            schedule = payload;
            schedule.ScheduleSHA256 = ...
                sixgr.util.sha256Hex(jsonencode(payload));
        end
    end
end

function tf = localNonnegativeInteger(value)
tf = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && value >= 0 && value == fix(value);
end

function tf = localPositiveInteger(value)
tf = localNonnegativeInteger(value) && value >= 1;
end

function tf = localAllocation(value)
tf = isnumeric(value) && isreal(value) && isequal(size(value),[1 2]) && ...
    all(isfinite(value)) && all(value == fix(value)) && value(1) >= 0 && value(2) > 0;
end
