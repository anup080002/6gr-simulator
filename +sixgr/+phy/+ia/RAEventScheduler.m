classdef RAEventScheduler
    %RAEVENTSCHEDULER Event-driven slot ownership for bounded four-step RA.

    methods (Static)
        function schedule = resolve(varargin)
            p = inputParser;
            p.FunctionName = "sixgr.phy.ia.RAEventScheduler.resolve";
            addParameter(p, "PRACHOccasionEndSlot", NaN, ...
                @localNonnegativeInteger);
            addParameter(p, "RAResponseWindowSlots", NaN, ...
                @localPositiveInteger);
            addParameter(p, "RARProcessingDelaySlots", NaN, ...
                @localPositiveInteger);
            addParameter(p, "Msg3K2Slots", NaN, ...
                @localPositiveInteger);
            addParameter(p, "Msg4ProcessingDelaySlots", NaN, ...
                @localNonnegativeInteger);
            addParameter(p, "ContentionResolutionTimerSlots", NaN, ...
                @localPositiveInteger);
            addParameter(p, "SetupCompleteK2Slots", NaN, ...
                @localPositiveInteger);
            parse(p, varargin{:});
            opt = p.Results;

            responseStart = double(opt.PRACHOccasionEndSlot) + 1;
            responseLast = responseStart + ...
                double(opt.RAResponseWindowSlots) - 1;
            msg2 = double(opt.PRACHOccasionEndSlot) + ...
                double(opt.RARProcessingDelaySlots);
            if msg2 < responseStart || msg2 > responseLast
                error("sixgr:phy:ia:RAROutsideResponseWindow", ...
                    "Configured RAR processing delay schedules Msg2 at slot %d outside [%d,%d].", ...
                    msg2, responseStart, responseLast);
            end
            msg3 = msg2 + double(opt.Msg3K2Slots);
            msg4 = msg3 + double(opt.Msg4ProcessingDelaySlots);
            contentionExpiry = msg3 + ...
                double(opt.ContentionResolutionTimerSlots);
            if msg4 < msg3 || msg4 >= contentionExpiry
                error("sixgr:phy:ia:Msg4OutsideContentionWindow", ...
                    "Configured Msg4 processing schedules slot %d outside [%d,%d).", ...
                    msg4, msg3, contentionExpiry);
            end
            setupComplete = msg4 + ...
                double(opt.SetupCompleteK2Slots);
            payload = struct( ...
                "ContractVersion", "sixgr_ra_event_schedule_r18/v1", ...
                "Source", "configured_event_delays", ...
                "PRACHOccasionEndSlot", ...
                    double(opt.PRACHOccasionEndSlot), ...
                "ResponseWindowStartSlot", responseStart, ...
                "ResponseWindowLastSlot", responseLast, ...
                "RARProcessingDelaySlots", ...
                    double(opt.RARProcessingDelaySlots), ...
                "Msg2Slot", msg2, ...
                "Msg3K2Slots", double(opt.Msg3K2Slots), ...
                "Msg3Slot", msg3, ...
                "Msg4ProcessingDelaySlots", ...
                    double(opt.Msg4ProcessingDelaySlots), ...
                "Msg4Slot", msg4, ...
                "ContentionExpirySlotExclusive", contentionExpiry, ...
                "SetupCompleteK2Slots", ...
                    double(opt.SetupCompleteK2Slots), ...
                "SetupCompleteSlot", setupComplete, ...
                "ProxyUsed", false, "FallbackUsed", false, ...
                "Status", "resolved");
            schedule = payload;
            schedule.ScheduleSHA256 = ...
                sixgr.util.sha256Hex(jsonencode(payload));
        end
    end
end

function tf = localNonnegativeInteger(value)
tf = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && value >= 0 && value == fix(value);
end

function tf = localPositiveInteger(value)
tf = localNonnegativeInteger(value) && value >= 1;
end
