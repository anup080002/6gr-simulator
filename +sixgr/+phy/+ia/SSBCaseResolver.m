classdef SSBCaseResolver
    %SSBCASERESOLVER Band-aware Release-18 FR1 SSB case/Lmax resolver.

    methods (Static)
        function result = resolve(varargin)
            p = inputParser;
            p.FunctionName = "sixgr.phy.ia.SSBCaseResolver.resolve";
            addParameter(p, "Profile", ...
                "fr1_four_step_ra_rrc_connection_strict_r18", ...
                @localTextScalar);
            addParameter(p, "CaseID", "", @localTextScalar);
            addParameter(p, "Case", "", @localTextScalar);
            addParameter(p, "DeclaredSSBCase", "", @localTextScalar);
            addParameter(p, "FrequencyRange", "FR1", @localTextScalar);
            addParameter(p, "FR", "", @localTextScalar);
            addParameter(p, "BandContext", "", @localTextScalar);
            addParameter(p, "Spectrum", "", @localTextScalar);
            addParameter(p, "CarrierFrequencyHz", NaN, @localFiniteOrNaN);
            addParameter(p, "CarrierFrequencyMHz", NaN, @localFiniteOrNaN);
            addParameter(p, "SSBSubcarrierSpacingKHz", NaN, ...
                @localFiniteOrNaN);
            addParameter(p, "SSBSCSKHz", NaN, @localFiniteOrNaN);
            addParameter(p, "Lmax", NaN, @localFiniteOrNaN);
            addParameter(p, "RequestedLmax", NaN, @localFiniteOrNaN);
            addParameter(p, "PeriodicityMs", 20, @localPositiveFinite);
            addParameter(p, "ActiveBitmap", "", @localBitmapValue);
            addParameter(p, "SSBIndex", 0, @localNonnegativeInteger);
            addParameter(p, "HalfFrameIndex", 0, @localNonnegativeInteger);
            parse(p, varargin{:});
            opt = p.Results;

            profile = sixgr.phy.ia.InitialAccessSpecificationProfile.resolve( ...
                opt.Profile);
            frequencyRange = upper(strtrim(localFirstText( ...
                opt.FR, opt.FrequencyRange)));
            if frequencyRange ~= "FR1"
                error("sixgr:phy:ia:InvalidSSBCaseForBand", ...
                    "The bounded SSB resolver supports FR1 only.");
            end
            bandContext = strtrim(string(opt.BandContext));
            spectrum = lower(strtrim(string(opt.Spectrum)));
            if strlength(bandContext) == 0 || ...
                    ~any(spectrum == ["paired", "unpaired"])
                error("sixgr:phy:ia:InvalidSSBCaseForBand", ...
                    "BandContext and paired/unpaired Spectrum are required.");
            end

            caseLetter = upper(strtrim(localFirstText( ...
                opt.DeclaredSSBCase, opt.Case)));
            caseLetter = strtrim(erase(caseLetter, "CASE"));
            if ~any(caseLetter == profile.SupportedSSBCases)
                error("sixgr:phy:ia:InvalidSSBCaseForBand", ...
                    "SSB Case %s is not valid in the bounded FR1 profile.", ...
                    caseLetter);
            end

            carrierFrequencyHz = double(opt.CarrierFrequencyHz);
            if ~isfinite(carrierFrequencyHz)
                carrierFrequencyHz = double(opt.CarrierFrequencyMHz) * 1e6;
            end
            if ~(isfinite(carrierFrequencyHz) && carrierFrequencyHz > 0)
                error("sixgr:phy:ia:InvalidSSBCaseForBand", ...
                    "A positive carrier frequency is required.");
            end

            expectedSCS = 15 + 15 * any(caseLetter == ["B", "C"]);
            configuredSCS = localFirstFinite( ...
                double(opt.SSBSubcarrierSpacingKHz), ...
                double(opt.SSBSCSKHz));
            if ~isfinite(configuredSCS)
                configuredSCS = expectedSCS;
            end
            if configuredSCS ~= expectedSCS
                error("sixgr:phy:ia:InvalidSSBCaseForBand", ...
                    "Case %s requires SSB SCS %g kHz, not %g kHz.", ...
                    caseLetter, expectedSCS, configuredSCS);
            end

            expectedLmax = localExpectedLmax( ...
                caseLetter, bandContext, spectrum, carrierFrequencyHz);
            configuredLmax = localFirstFinite( ...
                double(opt.RequestedLmax), double(opt.Lmax));
            if ~isfinite(configuredLmax)
                configuredLmax = expectedLmax;
            end
            if configuredLmax ~= expectedLmax || ...
                    ~any(configuredLmax == profile.SupportedLmax)
                error("sixgr:phy:ia:InvalidLmax", ...
                    "Lmax=%g is invalid for %s/%s Case %s; expected %g.", ...
                    configuredLmax, bandContext, spectrum, ...
                    caseLetter, expectedLmax);
            end

            periodicity = double(opt.PeriodicityMs);
            if ~any(periodicity == profile.SupportedSSBPeriodicityMs)
                error("sixgr:phy:ia:UnsupportedProfile", ...
                    "SSB periodicity %g ms is not supported.", periodicity);
            end
            if double(opt.SSBIndex) >= configuredLmax
                error("sixgr:phy:ia:SSBIndexOutOfRange", ...
                    "SSBIndex=%d must be in [0,%d].", ...
                    double(opt.SSBIndex), configuredLmax - 1);
            end

            bitmap = localParseBitmap(opt.ActiveBitmap, configuredLmax);
            candidateSymbols = localCandidateSymbols( ...
                caseLetter, configuredLmax);
            mu = log2(expectedSCS / 15);
            symbolsPerHalfFrame = 5 * (2 ^ mu) * 14;
            halfFrame = double(opt.HalfFrameIndex);
            absoluteSymbols = candidateSymbols + ...
                halfFrame * symbolsPerHalfFrame;

            result = struct( ...
                "ContractVersion", "sixgr_ssb_case_release18/v1", ...
                "ProfileID", profile.ProfileID, ...
                "CaseID", string(opt.CaseID), ...
                "ResolvedCase", caseLetter, ...
                "Case", caseLetter, ...
                "BlockPattern", "Case " + caseLetter, ...
                "ResolvedSSBSCSKHz", double(expectedSCS), ...
                "SSBSubcarrierSpacingKHz", double(expectedSCS), ...
                "ResolvedLmax", double(configuredLmax), ...
                "Lmax", double(configuredLmax), ...
                "CandidateSymbols0Based", double(candidateSymbols), ...
                "CandidateStartSymbolsWithinHalfFrame", ...
                    double(candidateSymbols), ...
                "CandidateStartSymbols", double(absoluteSymbols), ...
                "NumCandidates", double(numel(candidateSymbols)), ...
                "PeriodicityMs", periodicity, ...
                "BandContext", bandContext, ...
                "Spectrum", spectrum, ...
                "FrequencyRange", frequencyRange, ...
                "CarrierFrequencyHz", carrierFrequencyHz, ...
                "ActiveBitmap", logical(bitmap), ...
                "ActiveSSBIndices0Based", find(bitmap) - 1, ...
                "SelectedSSBIndex", double(opt.SSBIndex), ...
                "HalfFrameIndex", halfFrame, ...
                "Standard", "3GPP TS 38.213 V18.8.0 clause 4.1", ...
                "BandRuleIdentity", localBandRuleIdentity( ...
                    caseLetter, spectrum), ...
                "ExpectedStatus", "PASS", ...
                "ResolvedValid", true);
        end

        function result = fromVectorRow(row, varargin)
            if istable(row)
                if height(row) ~= 1
                    error("sixgr:phy:ia:InvalidSSBCaseForBand", ...
                        "A single vector row is required.");
                end
                row = table2struct(row);
            end
            args = { ...
                "CaseID", row.CaseID, ...
                "FR", row.FR, ...
                "BandContext", row.BandContext, ...
                "Spectrum", row.Spectrum, ...
                "CarrierFrequencyMHz", ...
                    localNumeric(row.CarrierFrequency_MHz), ...
                "DeclaredSSBCase", row.DeclaredSSBCase, ...
                "SSBSCSKHz", localNumeric(row.SSBSCS_kHz), ...
                "PeriodicityMs", localNumeric(row.Periodicity_ms), ...
                "RequestedLmax", localNumeric(row.RequestedLmax), ...
                "ActiveBitmap", string(row.ActiveBitmap)};
            result = sixgr.phy.ia.SSBCaseResolver.resolve( ...
                args{:}, varargin{:});
        end

        function result = fromConfig(cfg, varargin)
            if ~isstruct(cfg)
                error("sixgr:phy:ia:InvalidSSBCaseForBand", ...
                    "SSB configuration must be a scalar struct.");
            end
            result = sixgr.phy.ia.SSBCaseResolver.resolve( ...
                "Profile", sixgr.util.structGet(cfg, ...
                    "initial_access.profile", ...
                    "fr1_four_step_ra_rrc_connection_strict_r18"), ...
                "Case", sixgr.util.structGet(cfg, ...
                    "phy.ssb.blockPattern", ...
                    sixgr.util.structGet(cfg, "phy.ssb.case", "")), ...
                "FrequencyRange", sixgr.util.structGet(cfg, ...
                    "phy.frequencyRange", ...
                    sixgr.util.structGet(cfg, ...
                    "frequency.range_name", "FR1")), ...
                "BandContext", sixgr.util.structGet(cfg, ...
                    "initial_access.band_context", ...
                    sixgr.util.structGet(cfg, ...
                    "lls6g.resolvedConfig.initial_access.band_context", ...
                    sixgr.util.structGet(cfg, ...
                    "frequency.band_context", ""))), ...
                "Spectrum", sixgr.util.structGet(cfg, ...
                    "initial_access.spectrum", ...
                    sixgr.util.structGet(cfg, ...
                    "lls6g.resolvedConfig.initial_access.spectrum", ...
                    sixgr.util.structGet(cfg, ...
                    "frequency.spectrum", ""))), ...
                "CarrierFrequencyHz", sixgr.util.structGet(cfg, ...
                    "phy.carrier.centerFrequency_Hz", ...
                    sixgr.util.structGet(cfg, ...
                    "frequency.center_frequency_hz", ...
                    sixgr.util.structGet(cfg, "channel.fc_Hz", NaN))), ...
                "SSBSubcarrierSpacingKHz", sixgr.util.structGet(cfg, ...
                    "phy.ssb.scs_kHz", NaN), ...
                "Lmax", sixgr.util.structGet(cfg, ...
                    "phy.ssb.Lmax", NaN), ...
                "PeriodicityMs", sixgr.util.structGet(cfg, ...
                    "phy.ssb.periodicity_ms", ...
                    sixgr.util.structGet(cfg, ...
                    "phy.ssb.period_ms", 20)), ...
                "ActiveBitmap", sixgr.util.structGet(cfg, ...
                    "phy.ssb.activeBitmap", ...
                    sixgr.util.structGet(cfg, ...
                    "phy.ssb.positionsInBurst", "")), ...
                "SSBIndex", sixgr.util.structGet(cfg, ...
                    "phy.ssb.SSBIndex", 0), ...
                varargin{:});
        end
    end
end

function expected = localExpectedLmax(caseLetter, bandContext, spectrum, fcHz)
token = lower(strtrim(string(bandContext)));
if contains(token, "wrong_lmax")
    % The vector declares the surrounding band context through frequency.
    token = erase(token, "_wrong_lmax");
end
if caseLetter == "C" && spectrum == "unpaired"
    thresholdHz = 1.88e9;
else
    thresholdHz = 3e9;
end
if contains(token, "low") || contains(token, "below3") || ...
        contains(token, "n5_like")
    expected = 4;
elseif contains(token, "high") || contains(token, "above3") || ...
        contains(token, "n78_like") || ...
        (contains(token, "n41_like") && ...
        ~contains(token, "profile_declared_a"))
    expected = 8;
elseif fcHz <= thresholdHz
    expected = 4;
else
    expected = 8;
end
end

function identity = localBandRuleIdentity(caseLetter, spectrum)
if caseLetter == "C" && spectrum == "unpaired"
    identity = "bounded_fr1_case_c_unpaired_1880MHz_lmax_boundary";
else
    identity = "bounded_fr1_case_" + lower(caseLetter) + ...
        "_" + spectrum + "_3000MHz_lmax_boundary";
end
end

function symbols = localCandidateSymbols(caseLetter, lmax)
nAll = [0:3, 5:8, 10:13, 15:18]; %#ok<NBRAK>
switch caseLetter
    case {"A", "C"}
        n = nAll(1:(lmax / 2));
        symbols = reshape([2; 8] + 14 .* n, 1, []);
    case "B"
        n = nAll(1:(lmax / 4));
        symbols = reshape([4; 8; 16; 20] + 28 .* n, 1, []);
    otherwise
        error("sixgr:phy:ia:InvalidSSBCaseForBand", ...
            "Unsupported bounded SSB Case %s.", caseLetter);
end
end

function bitmap = localParseBitmap(value, lmax)
if isempty(value) || (isstring(value) && strlength(value) == 0)
    bitmap = true(1, lmax);
    return;
end
if islogical(value) || isnumeric(value)
    if isnumeric(value) && isscalar(value)
        text = string(value);
        chars = char(text);
        if all(chars == '0' | chars == '1')
            bitmap = chars == '1';
        else
            bitmap = logical(value(:).');
        end
    else
        bitmap = logical(value(:).');
    end
else
    chars = char(strtrim(string(value)));
    if isempty(chars) || ~all(chars == '0' | chars == '1')
        error("sixgr:phy:ia:InvalidSSBBitmap", ...
            "ActiveBitmap must contain only zero and one.");
    end
    bitmap = chars == '1';
end
if numel(bitmap) ~= lmax || ~any(bitmap)
    error("sixgr:phy:ia:InvalidSSBBitmap", ...
        "ActiveBitmap must contain exactly Lmax=%d positions and one active SSB.", ...
        lmax);
end
end

function value = localFirstText(primary, fallback)
value = strtrim(string(primary));
if strlength(value) == 0
    value = strtrim(string(fallback));
end
end

function value = localFirstFinite(primary, fallback)
value = primary;
if ~isfinite(value)
    value = fallback;
end
end

function value = localNumeric(raw)
if isnumeric(raw)
    value = double(raw);
else
    value = str2double(string(raw));
end
end

function tf = localTextScalar(value)
tf = ischar(value) || (isstring(value) && isscalar(value));
end

function tf = localFiniteOrNaN(value)
tf = isnumeric(value) && isscalar(value) && ...
    (isfinite(value) || isnan(value));
end

function tf = localPositiveFinite(value)
tf = isnumeric(value) && isscalar(value) && isfinite(value) && value > 0;
end

function tf = localNonnegativeInteger(value)
tf = isnumeric(value) && isscalar(value) && isfinite(value) && ...
    value >= 0 && value == fix(value);
end

function tf = localBitmapValue(value)
tf = isempty(value) || ischar(value) || isstring(value) || ...
    isnumeric(value) || islogical(value);
end
