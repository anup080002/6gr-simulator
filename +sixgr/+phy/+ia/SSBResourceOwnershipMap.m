classdef SSBResourceOwnershipMap
    %SSBRESOURCEOWNERSHIPMAP Exact 240-by-4 SS/PBCH RE ownership.

    methods (Static)
        function result = resolve(nCellID)
            if nargin < 1 || ~(isnumeric(nCellID) && isscalar(nCellID) && ...
                    isfinite(nCellID) && nCellID >= 0 && ...
                    nCellID <= 1007 && nCellID == fix(nCellID))
                error("sixgr:phy:ia:InvalidCarrierGrid", ...
                    "NCellID must be an integer in [0,1007].");
            end
            v = mod(double(nCellID), 4);
            owner = repmat("ZERO", 4, 240);
            owner(1, 57:183) = "PSS";
            owner(3, 57:183) = "SSS";

            for symbol0 = [1, 3]
                owner(symbol0 + 1, :) = "PBCH";
                dmrsSubcarriers0 = v:4:239;
                owner(symbol0 + 1, dmrsSubcarriers0 + 1) = "PBCH_DMRS";
            end
            pbchEdge0 = [0:47, 192:239]; %#ok<NBRAK>
            owner(3, pbchEdge0 + 1) = "PBCH";
            dmrsEdge0 = v:4:239;
            dmrsEdge0 = dmrsEdge0(dmrsEdge0 <= 47 | dmrsEdge0 >= 192);
            owner(3, dmrsEdge0 + 1) = "PBCH_DMRS";

            symbol0 = repelem((0:3).', 240);
            subcarrier0 = repmat((0:239).', 4, 1);
            ownerColumn = reshape(owner.', [], 1);
            index0 = symbol0 * 240 + subcarrier0;
            tableOut = table( ...
                symbol0, subcarrier0, ownerColumn, ...
                repmat(v, 960, 1), index0, ...
                'VariableNames', { ...
                'Symbol0', 'Subcarrier0', 'Owner', ...
                'NCellIDMod4', 'Index0'});
            counts = groupsummary(tableOut, "Owner");
            payload = strjoin( ...
                string(tableOut.Symbol0) + "," + ...
                string(tableOut.Subcarrier0) + "," + tableOut.Owner, ...
                newline);
            result = struct( ...
                "ContractVersion", "sixgr_ssb_re_ownership/v1", ...
                "Standard", "3GPP TS 38.211 V18.8.0 clauses 7.4.3-7.4.4", ...
                "NCellID", double(nCellID), ...
                "NCellIDMod4", v, ...
                "NumSubcarriers", 240, ...
                "NumSymbols", 4, ...
                "Rows", tableOut, ...
                "Counts", counts, ...
                "MapSHA256", sixgr.util.sha256Hex(payload));
        end
    end
end
