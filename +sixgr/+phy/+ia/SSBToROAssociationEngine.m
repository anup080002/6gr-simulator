classdef SSBToROAssociationEngine
    %SSBTOROASSOCIATIONENGINE Bounded sequential SSB-to-RO mapping floor.
    %
    % This implements the independently supplied sequential association
    % floor for the declared 1/8 through 16 SSB-per-RO ratios. It does not
    % claim the still-missing complete TS 38.213 association-period oracle.

    methods (Static)
        function result = resolve(varargin)
            p = inputParser;
            p.FunctionName = ...
                "sixgr.phy.ia.SSBToROAssociationEngine.resolve";
            addParameter(p, "RatioName", "", @localTextScalar);
            addParameter(p, "SSBsPerRONumerator", ...
                NaN, @localPositiveInteger);
            addParameter(p, "SSBsPerRODenominator", ...
                NaN, @localPositiveInteger);
            addParameter(p, "NumActiveSSBs", ...
                NaN, @localPositiveInteger);
            addParameter(p, "SSBOrdinal0", ...
                NaN, @localNonnegativeInteger);
            addParameter(p, "CBPreamblesPerSSB", ...
                NaN, @localPositiveInteger);
            addParameter(p, "AssociationPeriodROCount", ...
                NaN, @localPositiveInteger);
            parse(p, varargin{:});
            opt = p.Results;

            numerator = double(opt.SSBsPerRONumerator);
            denominator = double(opt.SSBsPerRODenominator);
            ratio = numerator / denominator;
            if ~any(ratio == [1/8 1/4 1/2 1 2 4 8 16])
                error("sixgr:phy:ia:NoPRACHOccasion", ...
                    "The SSB-per-RO ratio %d/%d is outside the bounded profile.", ...
                    numerator, denominator);
            end
            ordinal = double(opt.SSBOrdinal0);
            if ordinal >= double(opt.NumActiveSSBs)
                error("sixgr:phy:ia:NoPRACHOccasion", ...
                    "SSB ordinal %d is outside %d active SSBs.", ...
                    ordinal, double(opt.NumActiveSSBs));
            end

            if numerator < denominator
                roPerSSB = denominator / numerator;
                roOrdinals = ordinal * roPerSSB + (0:roPerSSB-1);
                position = 0;
                preambleStart = 0;
            else
                ssbPerRO = numerator / denominator;
                roOrdinals = floor(ordinal / ssbPerRO);
                position = mod(ordinal, ssbPerRO);
                preambleStart = ...
                    position * double(opt.CBPreamblesPerSSB);
            end
            if any(roOrdinals >= double(opt.AssociationPeriodROCount))
                error("sixgr:phy:ia:NoPRACHOccasion", ...
                    "Association period contains %d ROs but SSB %d maps to %s.", ...
                    double(opt.AssociationPeriodROCount), ordinal, ...
                    strjoin(string(roOrdinals), "|"));
            end

            payload = struct( ...
                "ContractVersion", ...
                    "sixgr_ssb_ro_sequential_floor/v1", ...
                "RatioName", string(opt.RatioName), ...
                "SSBsPerRONumerator", numerator, ...
                "SSBsPerRODenominator", denominator, ...
                "NumActiveSSBs", double(opt.NumActiveSSBs), ...
                "SSBOrdinal0", ordinal, ...
                "CBPreamblesPerSSB", ...
                    double(opt.CBPreamblesPerSSB), ...
                "AssociationPeriodROCount", ...
                    double(opt.AssociationPeriodROCount), ...
                "ROOrdinals0", double(roOrdinals), ...
                "ROOrdinalsText", strjoin(string(roOrdinals), "|"), ...
                "SSBPositionWithinRO0", double(position), ...
                "PreambleStart0", double(preambleStart), ...
                "PreambleCount", double(opt.CBPreamblesPerSSB), ...
                "Scope", ...
                    "sequential_mapping_floor_full_38_213_association_still_required", ...
                "NormativeCompleteness", "bounded_floor_only", ...
                "ProxyUsed", false, ...
                "FallbackUsed", false, ...
                "Status", "resolved");
            result = payload;
            result.ResolutionSHA256 = ...
                sixgr.util.sha256Hex(jsonencode(payload));
        end
    end
end

function tf = localTextScalar(value)
tf = ischar(value) || (isstring(value) && isscalar(value));
end

function tf = localNonnegativeInteger(value)
tf = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && value >= 0 && value == fix(value);
end

function tf = localPositiveInteger(value)
tf = localNonnegativeInteger(value) && value >= 1;
end
