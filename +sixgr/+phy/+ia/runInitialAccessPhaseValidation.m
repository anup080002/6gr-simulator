function summary = runInitialAccessPhaseValidation(varargin)
%RUNINITIALACCESSPHASEVALIDATION Execute the bounded Release-18 IA phase.

ip = inputParser;
ip.FunctionName = "sixgr.phy.ia.runInitialAccessPhaseValidation";
ip.addParameter("VectorRoot", ...
    fullfile(pwd, "tests", "vectors", "initial_access"), ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));
ip.addParameter("OutputDir", ...
    fullfile(pwd, "artifacts", "initial_access_phase"), ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));
ip.addParameter("SeedList", [11 23 47 89], ...
    @(x) isnumeric(x) && isvector(x) && ~isempty(x));
ip.addParameter("ConfidenceLevel", 0.95, ...
    @(x) isnumeric(x) && isscalar(x) && isfinite(x) ...
    && x > 0 && x < 1);
ip.addParameter("Strict", true, ...
    @(x) islogical(x) && isscalar(x));
ip.parse(varargin{:});
opt = ip.Results;

vectorRoot = char(string(opt.VectorRoot));
outputDir = char(string(opt.OutputDir));
seedList = double(opt.SeedList(:).');
if ~isfolder(vectorRoot)
    error("sixgr:phy:ia:PhaseVectorRootMissing", ...
        "VectorRoot must identify the initial-access vector pack.");
end
if strlength(strtrim(string(outputDir))) == 0
    error("sixgr:phy:ia:PhaseOutputMissing", ...
        "OutputDir must be nonempty.");
end
if isfile(outputDir) || isfolder(outputDir)
    error("sixgr:phy:ia:PhaseOutputAlreadyExists", ...
        "OutputDir must not already exist; publication is transactional.");
end
if any(~isfinite(seedList) | seedList ~= fix(seedList))
    error("sixgr:phy:ia:PhaseSeedListInvalid", ...
        "SeedList must contain finite integers.");
end
if logical(opt.Strict) ~= true
    error("sixgr:phy:ia:StrictExecutionRequired", ...
        "The Phase 06 production report requires Strict=true.");
end

started = tic;
[vectorStatus, vectorOutput, vectorCommand] = localRunPython( ...
    fullfile(vectorRoot, "verify_initial_access_vector_pack.py"), "");
if vectorStatus ~= 0
    error("sixgr:phy:ia:VectorPackVerificationFailed", ...
        "Initial-access vector verification failed:\n%s", vectorOutput);
end

setup6GRSimToolkit("Verbose", false);
testSummary = localRunFocusedTests();

repoRoot = localRepositoryRoot();
scenarioPath = fullfile(repoRoot, "configs", "lls", ...
    "lls_ra_four_step_strict_mini_anchor.yaml");
scenario = sixgr.lls6g.config.loadScenarioConfig(scenarioPath);
cfg = sixgr.lls6g.buildInternalConfig(scenario, tempdir);
localValidateProductionConfig(cfg);

parentDir = fileparts(outputDir);
if isempty(parentDir)
    parentDir = pwd;
end
if ~isfolder(parentDir)
    [ok, message] = mkdir(parentDir);
    if ~ok
        error("sixgr:phy:ia:PhaseOutputParentCreateFailed", "%s", message);
    end
end
stageDir = tempname(parentDir);
[ok, message] = mkdir(stageDir);
if ~ok
    error("sixgr:phy:ia:PhaseStageCreateFailed", "%s", message);
end
cleanup = onCleanup(@() localRemoveStage(stageDir));

evidence = sixgr.phy.ia.InitialAccessPhaseEvidenceBuilder.build( ...
    vectorRoot, cfg, seedList, double(opt.ConfidenceLevel), testSummary);
exported = sixgr.phy.ia.InitialAccessArtifactExporter.exportBase( ...
    evidence, stageDir, vectorRoot);
if exported.CSVCount ~= 31 || exported.PNGCount ~= 20
    error("sixgr:phy:ia:PhaseArtifactCountMismatch", ...
        "Contracted output is %d CSV and %d PNG; expected 31 and 20.", ...
        exported.CSVCount, exported.PNGCount);
end

[artifactStatus, artifactOutput, artifactCommand] = localRunPython( ...
    fullfile(vectorRoot, "verify_initial_access_artifacts.py"), stageDir);
if artifactStatus ~= 0
    error("sixgr:phy:ia:ArtifactVerificationFailed", ...
        "Initial-access artifact verification failed:\n%s", ...
        artifactOutput);
end

inventory = localInventory(stageDir, exported);
[moved, moveMessage] = movefile(stageDir, outputDir);
if ~moved
    error("sixgr:phy:ia:PhasePublishFailed", ...
        "Unable to publish initial-access phase output: %s", moveMessage);
end
clear cleanup

summary = struct( ...
    "ContractVersion", "InitialAccessPhaseValidation/v1", ...
    "Passed", true, ...
    "VectorRoot", string(vectorRoot), ...
    "OutputDir", string(outputDir), ...
    "ScenarioPath", string(scenarioPath), ...
    "ScenarioID", string(scenario.ScenarioID), ...
    "ScenarioConfigHash", string(scenario.ConfigHash), ...
    "SeedList", seedList, ...
    "ConfidenceLevel", double(opt.ConfidenceLevel), ...
    "Strict", true, ...
    "MATLABRelease", string(version("-release")), ...
    "VectorPackVerificationCommand", string(vectorCommand), ...
    "VectorPackVerificationExitCode", double(vectorStatus), ...
    "VectorPackVerificationOutput", string(strtrim(vectorOutput)), ...
    "TestSummary", testSummary, ...
    "ContractedCSVCount", double(exported.CSVCount), ...
    "ContractedPNGCount", double(exported.PNGCount), ...
    "CSVFiles", exported.CSVFiles, ...
    "CSVRowCounts", exported.CSVRowCounts, ...
    "PNGFiles", exported.PNGFiles, ...
    "ArtifactVerifierCommand", string(artifactCommand), ...
    "ArtifactVerifierExitCode", double(artifactStatus), ...
    "ArtifactVerifierOutput", string(strtrim(artifactOutput)), ...
    "ArtifactInventory", inventory, ...
    "DurationSeconds", toc(started));
end

function summary = localRunFocusedTests()
root = localRepositoryRoot();
suiteNames = [ ...
    "testInitialAccessSSBPhaseCore"; ...
    "testInitialAccessMIBPhaseCore"; ...
    "testInitialAccessType0PhaseCore"; ...
    "testSIB1IndependentUPERVectors"; ...
    "testSIB1ASN1RoundTrip"; ...
    "testSIB1WaveformRecoveryAWGN"; ...
    "testInitialAccessRAPhaseCore"; ...
    "testInitialAccessRRCPhaseCore"; ...
    "testMsg3HARQ"; ...
    "testFourStepRACollisionAndCapture"; ...
    "testFourStepRAMultiAttempt"; ...
    "testInitialAccessMasterYAMLAuthority"];
summary = table( ...
    strings(0,1), zeros(0,1), zeros(0,1), zeros(0,1), ...
    zeros(0,1), zeros(0,1), zeros(0,1), ...
    'VariableNames', {'TestSuite','TestsRun','Passed','Failed', ...
    'Skipped','Blocked','Duration_s'});
legacyFunctionTests = [ ...
    "testSIB1ASN1RoundTrip"
    "testSIB1WaveformRecoveryAWGN"
    "testInitialAccessMasterYAMLAuthority"];
for index = 1:numel(suiteNames)
    suitePath = fullfile(root, "tests", suiteNames(index) + ".m");
    if ~isfile(suitePath)
        error("sixgr:phy:ia:FocusedTestMissing", ...
            "Required focused suite is missing: %s", suitePath);
    end
    if ismember(suiteNames(index), legacyFunctionTests)
        timer = tic;
        ok = feval(char(suiteNames(index)));
        duration = toc(timer);
        total = 1;
        passed = double(logical(ok));
        failed = double(~logical(ok));
        blocked = 0;
    else
        result = runtests(suitePath);
        failed = nnz([result.Failed]);
        blocked = nnz([result.Incomplete]);
        passed = nnz([result.Passed]);
        duration = sum([result.Duration]);
        total = numel(result);
    end
    if failed > 0 || blocked > 0 || passed ~= total
        error("sixgr:phy:ia:FocusedTestFailure", ...
            "%s: total=%d passed=%d failed=%d incomplete=%d.", ...
            suiteNames(index), total, passed, failed, blocked);
    end
    summary(end + 1, :) = { ... %#ok<AGROW>
        suiteNames(index), total, passed, failed, ...
        0, blocked, duration};
end
end

function localValidateProductionConfig(cfg)
required = [ ...
    "initial_access.enabled"; ...
    "initial_access.sib1.enabled"; ...
    "initial_access.rrc.require_setup_complete"; ...
    "random_access.enabled"; ...
    "random_access.setup_complete_pusch"; ...
    "frequency.range_name"; ...
    "frequency.band_name"];
missing = strings(0,1);
for pathName = required.'
    if isempty(sixgr.util.structGet(cfg, pathName, []))
        missing(end + 1,1) = pathName; %#ok<AGROW>
    end
end
if ~isempty(missing)
    error("sixgr:phy:ia:ProductionConfigIncomplete", ...
        "Strict production YAML is missing internal fields: %s", ...
        strjoin(missing, ", "));
end
end

function root = localRepositoryRoot()
root = fileparts(mfilename("fullpath"));
for index = 1:3
    root = fileparts(root);
end
if ~isfile(fullfile(root, "setup6GRSimToolkit.m"))
    error("sixgr:phy:ia:RepositoryRootNotFound", ...
        "Unable to locate the simulator repository root.");
end
end

function [status, output, command] = localRunPython(scriptPath, argument)
if ~isfile(scriptPath)
    error("sixgr:phy:ia:PythonVerifierMissing", ...
        "Python verifier is missing: %s", scriptPath);
end
command = """python"" """ + string(scriptPath) + """";
if strlength(string(argument)) > 0
    command = command + " """ + string(argument) + """";
end
[status, output] = system(char(command));
end

function inventory = localInventory(stageDir, exported)
names = [exported.CSVFiles(:); exported.PNGFiles(:)];
kind = [repmat("CSV", numel(exported.CSVFiles), 1); ...
    repmat("PNG", numel(exported.PNGFiles), 1)];
bytes = zeros(numel(names), 1);
hash = strings(numel(names), 1);
width = nan(numel(names), 1);
height = nan(numel(names), 1);
for index = 1:numel(names)
    pathName = fullfile(stageDir, names(index));
    if ~isfile(pathName)
        error("sixgr:phy:ia:PhaseInventoryMissing", ...
            "Expected final artifact is absent: %s", names(index));
    end
    metadata = dir(pathName);
    bytes(index) = metadata.bytes;
    hash(index) = localFileSHA256(pathName);
    if kind(index) == "PNG"
        image = imfinfo(pathName);
        width(index) = image.Width;
        height(index) = image.Height;
    end
end
inventory = table(names, kind, bytes, hash, width, height, ...
    repmat("PASS", numel(names), 1), ...
    'VariableNames', {'FileName','Kind','Bytes','SHA256', ...
    'Width','Height','Status'});
end

function hash = localFileSHA256(pathName)
fid = fopen(pathName, "rb");
if fid < 0
    error("sixgr:phy:ia:PhaseArtifactReadFailed", ...
        "Unable to read final artifact: %s", pathName);
end
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid, Inf, "*uint8");
hash = string(sixgr.util.sha256Hex(bytes));
clear cleanup
end

function localRemoveStage(pathName)
if isfolder(pathName)
    rmdir(pathName, "s");
end
end
