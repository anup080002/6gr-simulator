function result = recoverPBCH(rxSSBGrid,sync,bundle,cfg)
%RECOVERPBCH Run the production PBCH DM-RS/MMSE/polar/BCH chain.
phyCfg = sixgr.phy.ia.c0.config.toPHYConfig(cfg);
[pb,info] = sixgr.phy.dl.PBCH_Recovery(rxSSBGrid,sync,phyCfg, ...
    "PolarListLength",double(cfg.waveform.polar_list_length), ...
    "NoiseVarFloor",double(cfg.receiver.pbch_noise_variance_floor));
payloadMatch = logical(pb.Ok) && ...
    isequal(double(pb.TransportBlock(:)),double(bundle.TransportBlock(:)));
tested = 0;
if isfield(info,"PerCandidate")
    for k = 1:numel(info.PerCandidate)
        tested = tested + ~isempty(info.PerCandidate(k).ErrFlag);
    end
end
result = struct( ...
    "Ok",logical(pb.Ok) && payloadMatch, ...
    "CRCError",double(~logical(pb.Ok)), ...
    "PayloadMatch",payloadMatch, ...
    "BitErrors",double(sum(double(pb.TransportBlock(:))~=double(bundle.TransportBlock(:)))), ...
    "PBCH",pb, ...
    "Info",info, ...
    "ChannelEstimateAvailable",logical(pb.ChannelEstimateAvailable), ...
    "NoiseVariance",double(pb.NoiseVar), ...
    "ReceiverSINRDB",double(pb.ReceiverHestSINR_dB), ...
    "PostEqSINRDB",double(pb.PostEqSINR_dB));
result.DMRSHypothesesTested = double(tested);
result.PolarDecodes = double(tested);
end
