function result = declarationMetrics(sync,cfg,thresholds)
%DECLARATIONMETRICS Reduce the complete blind PSS/SSS cell declaration.
% A cell-with-PCI declaration is made only after both the calibrated PSS
% pre-stage and the calibrated joint PSS/SSS statistic pass.
if nargin < 3 || isempty(thresholds)
    thresholds = struct("PSSStageThreshold",-Inf, ...
        "GlobalDeclarationThreshold",-Inf);
elseif isnumeric(thresholds) && isscalar(thresholds)
    thresholds = struct("PSSStageThreshold",double(thresholds), ...
        "GlobalDeclarationThreshold",double(thresholds));
end
pssMetric = double(sixgr.util.structGet(sync,"FreqInfo.Metric",NaN));
sss = sixgr.util.structGet(sync,"SSSInfo",struct());
sssMetric = double(sixgr.util.structGet(sss,"Metric",NaN));
nRx = double(sixgr.util.structGet(sss,"NumberReceiveAntennas",1));
sssNormalized = sssMetric/max(nRx,1);
sssMargin = double(sixgr.util.structGet(sss,"MetricMargin",NaN))/max(nRx,1);
switch lower(string(cfg.search.declaration_statistic))
    case "minimum_pss_sss_normalized_metric"
        jointMetric = min(pssMetric,sssNormalized);
    otherwise
        error("sixgr:phy:ia:c0:receiver:DeclarationStatistic", ...
            "Unsupported C0 declaration statistic '%s'.", ...
            string(cfg.search.declaration_statistic));
end
pssThreshold = double(sixgr.util.structGet( ...
    thresholds,"PSSStageThreshold",-Inf));
globalThreshold = double(sixgr.util.structGet( ...
    thresholds,"GlobalDeclarationThreshold", ...
    sixgr.util.structGet(thresholds,"Threshold",-Inf)));
pssStagePassed = isfinite(pssMetric) && pssMetric >= pssThreshold;
sssStagePassed = isfinite(sssNormalized) && ...
    sssNormalized >= double(cfg.search.sss_normalized_metric_floor);
cellDeclared = pssStagePassed && sssStagePassed && ...
    isfinite(jointMetric) && jointMetric >= globalThreshold;
result = struct( ...
    "PSSMetric",pssMetric, ...
    "PSSStageThreshold",pssThreshold, ...
    "PSSStagePassed",logical(pssStagePassed), ...
    "SSSNormalizedMetric",sssNormalized, ...
    "SSSNormalizedMetricMargin",sssMargin, ...
    "SSSStageThreshold",double(cfg.search.sss_normalized_metric_floor), ...
    "SSSStagePassed",logical(sssStagePassed), ...
    "JointDeclarationStatistic",double(jointMetric), ...
    "GlobalDeclarationThreshold",globalThreshold, ...
    "CellDeclared",logical(cellDeclared), ...
    "StatisticDefinition",string(cfg.search.declaration_statistic));
end
