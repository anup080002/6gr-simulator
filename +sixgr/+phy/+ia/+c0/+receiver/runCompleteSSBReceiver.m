function result = runCompleteSSBReceiver(rxWaveform,bundle,cfg,thresholds,varargin)
%RUNCOMPLETESSBRECEIVER Production blind PSS/SSS/PBCH C0 receiver.
p = inputParser;
p.addParameter("TrueCFOHz",NaN,@(x)isnumeric(x)&&isscalar(x));
p.addParameter("TrueTimingSamples",NaN,@(x)isnumeric(x)&&isscalar(x));
p.parse(varargin{:});
phyCfg = sixgr.phy.ia.c0.config.toPHYConfig(cfg);
phyCfg.phy.sampleRate_Hz = bundle.SampleRateHz;
pbch = struct("Ok",false,"CRCError",1,"PayloadMatch",false, ...
    "BitErrors",double(cfg.waveform.pbch_payload_bits), ...
    "ChannelEstimateAvailable",false,"NoiseVariance",NaN, ...
    "ReceiverSINRDB",NaN,"PostEqSINRDB",NaN, ...
    "DMRSHypothesesTested",0,"PolarDecodes",0);
failure = "";
declaration = struct("PSSMetric",NaN,"PSSStageThreshold",NaN, ...
    "PSSStagePassed",false,"SSSNormalizedMetric",NaN, ...
    "SSSNormalizedMetricMargin",NaN,"SSSStageThreshold",NaN, ...
    "SSSStagePassed",false,"JointDeclarationStatistic",NaN, ...
    "GlobalDeclarationThreshold",NaN,"CellDeclared",false, ...
    "StatisticDefinition",string(cfg.search.declaration_statistic));
try
    [rxSSBGrid,sync] = sixgr.phy.dl.SSB_Rx(rxWaveform,phyCfg, ...
        "SampleRate_Hz",bundle.SampleRateHz);
    declaration = sixgr.phy.ia.c0.receiver.declarationMetrics( ...
        sync,cfg,thresholds);
    pssMetric = double(declaration.PSSMetric);
    pssDetected = logical(declaration.PSSStagePassed);
    cellDeclared = logical(declaration.CellDeclared);
    pssIdentityCorrect = double(sync.NID2) == double(bundle.NID2);
    sssCorrect = double(sync.NCellID) == double(bundle.NCellID);
    if cellDeclared && pssIdentityCorrect && sssCorrect
        pbch = sixgr.phy.ia.c0.receiver.recoverPBCH( ...
            rxSSBGrid,sync,bundle,cfg);
    end
catch ME
    sync = struct();
    rxSSBGrid = complex(zeros(0,0,0));
    pssMetric = NaN;
    pssDetected = false;
    cellDeclared = false;
    pssIdentityCorrect = false;
    sssCorrect = false;
    failure = string(ME.identifier)+":"+string(ME.message);
end
timingEstimate = double(sixgr.util.structGet(sync,"TimingOffset",NaN));
cfoEstimate = double(sixgr.util.structGet(sync,"FreqOffset_Hz",NaN));
freqInfo = sixgr.util.structGet(sync,"FreqInfo",struct());
searchHypotheses = double(numel(sixgr.util.structGet(freqInfo,"Candidates_Hz",[]))* ...
    numel(sixgr.util.structGet(freqInfo,"Candidates_NID2",[]))* ...
    size(sixgr.util.structGet(freqInfo,"CandidateSearchWindows",zeros(0,2)),1));
if strlength(failure) == 0
    if ~pssDetected
        failure = "pss_below_global_threshold";
    elseif ~cellDeclared
        failure = "joint_pss_sss_below_global_threshold";
    elseif ~pssIdentityCorrect
        failure = "pss_identity_mismatch";
    elseif ~sssCorrect
        failure = "sss_pci_mismatch";
    elseif ~logical(pbch.Ok)
        failure = "pbch_crc_or_payload_mismatch";
    end
end
result = struct( ...
    "PSSMetric",pssMetric, ...
    "PSSDetected",pssDetected, ...
    "CellDeclared",cellDeclared, ...
    "NoCellDeclared",~cellDeclared, ...
    "PSSIdentityCorrect",pssIdentityCorrect, ...
    "SSSCorrect",sssCorrect, ...
    "CorrectPCIDeclared",cellDeclared && pssIdentityCorrect && sssCorrect, ...
    "WrongPCIDeclared",cellDeclared && ~(pssIdentityCorrect && sssCorrect), ...
    "WrongPCI",cellDeclared && ~(pssIdentityCorrect && sssCorrect), ...
    "PBCHAttempted",cellDeclared && pssIdentityCorrect && sssCorrect, ...
    "PBCHOk",logical(pbch.Ok), ...
    "CompleteSSBSuccess",cellDeclared && pssIdentityCorrect && sssCorrect && logical(pbch.Ok), ...
    "TimingEstimateSamples",timingEstimate, ...
    "TimingErrorSamples",timingEstimate-double(p.Results.TrueTimingSamples), ...
    "CFOEstimateHz",cfoEstimate, ...
    "CFOErrorHz",cfoEstimate-double(p.Results.TrueCFOHz), ...
    "SearchHypotheses",searchHypotheses, ...
    "Declaration",declaration, ...
    "PBCH",pbch, ...
    "Sync",sync, ...
    "RxSSBGrid",rxSSBGrid, ...
    "FailureReason",failure, ...
    "EvidenceClass","actual_nr_ssb_waveform_receiver_truth", ...
    "ApproximationMode","none");
end
