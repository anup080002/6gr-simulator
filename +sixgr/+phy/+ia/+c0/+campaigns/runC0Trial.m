function row = runC0Trial(bundle,cfg,snrDB,trialIndex,thresholds)
%RUNC0TRIAL Execute one production IA end-to-end C0 realization.
if isnumeric(thresholds) && isscalar(thresholds)
    thresholds=struct("PSSStageThreshold",double(thresholds), ...
        "GlobalDeclarationThreshold",double(thresholds));
end
seedAllocation = sixgr.phy.ia.c0.util.trialSeeds(cfg,snrDB,trialIndex);
channelSeed = seedAllocation.Channel;
cfoSeed = seedAllocation.CFO;
noiseSeed = seedAllocation.Noise;
timingSeed = seedAllocation.Timing;

channel = sixgr.phy.ia.c0.channel.applyFading( ...
    bundle.Waveform,bundle,cfg,channelSeed);
old = rng;
cleanup = onCleanup(@()rng(old));
rng(timingSeed,"twister");
timingBudget = double(cfg.search.timing_uncertainty_samples);
channelTiming = double(channel.TimingOffsetSamples);
remainingTimingBudget = floor(timingBudget-channelTiming);
if remainingTimingBudget < 0
    error("sixgr:phy:ia:c0:campaign:ChannelDelayOutsideTimingBudget", ...
        "The physical channel timing offset (%g samples) exceeds the configured total timing uncertainty (%g samples). Increase search.timing_uncertainty_samples in YAML.", ...
        channelTiming,timingBudget);
end
% search.timing_uncertainty_samples is the total receiver uncertainty,
% including the physical fading-channel delay. Do not add an independent
% random delay on top of that budget.
timingPad = randi([0 remainingTimingBudget]);
cleanNoCFO = [complex(zeros(timingPad,size(channel.Waveform,2)));channel.Waveform];
cfgRuntime = cfg;
cfgRuntime.runtime = struct("sample_rate_hz",bundle.SampleRateHz);
[cleanWithCFO,cfo] = sixgr.phy.ia.c0.impairments.applyOscillatorCFO( ...
    cleanNoCFO,cfgRuntime,cfoSeed);
measurementStart = timingPad+channelTiming;
[signalREPower,~] = sixgr.phy.ia.c0.channel.measureActiveREPower( ...
    cleanNoCFO,bundle,measurementStart);
[received,noise,noiseMeta] = sixgr.phy.ia.c0.channel.addNoiseForTargetSNR( ...
    cleanWithCFO,bundle,signalREPower,snrDB,noiseSeed);
[noiseREPower,~] = sixgr.phy.ia.c0.channel.measureActiveREPower( ...
    noise,bundle,measurementStart);
measuredSNRDB = 10*log10(signalREPower/max(noiseREPower,realmin));
symbolLengths = double(bundle.OFDMInfo.SymbolLengths(:));
pssPrefix = sum(symbolLengths(1:double(bundle.CandidateStartSymbol)));
trueTiming = measurementStart+pssPrefix;
receiver = sixgr.phy.ia.c0.receiver.runCompleteSSBReceiver( ...
    received,bundle,cfg,thresholds, ...
    "TrueCFOHz",cfo.AppliedCFOHz,"TrueTimingSamples",trueTiming);
componentPBCH = sixgr.phy.ia.c0.receiver.runPBCHComponentReceiver( ...
    received,bundle,cfg,receiver.CFOEstimateHz,trueTiming);
oracle = sixgr.phy.ia.c0.receiver.runOracleReceiver( ...
    received,bundle,cfg,cfo.AppliedCFOHz,trueTiming);
[channelMSE,channelMSEMeta] = sixgr.phy.ia.c0.receiver.channelEstimateMSE( ...
    receiver,cleanWithCFO,bundle,cfg);
detectedOccurrence=double(sixgr.util.structGet( ...
    receiver,"Sync.SelectedCandidateStartSymbol",NaN));
trueOccurrence=double(bundle.CandidateStartSymbol);
correctOccurrence=isfinite(detectedOccurrence)&&detectedOccurrence==trueOccurrence;
correctJointSS=logical(receiver.CellDeclared)&&logical(receiver.PSSIdentityCorrect)&& ...
    logical(receiver.SSSCorrect);
conditionalSSSEligible=logical(receiver.PSSDetected)&& ...
    logical(receiver.PSSIdentityCorrect);
conditionalSSSSuccess=conditionalSSSEligible&& ...
    logical(receiver.Declaration.SSSStagePassed)&&correctJointSS;
minimumCP=min(double(bundle.OFDMInfo.SymbolLengths(:)))-double(bundle.OFDMInfo.Nfft);
timingTolerance=max(1,floor(double(cfg.receiver.timing_success_tolerance_fraction_min_cp)*minimumCP));
timingValid=correctJointSS&&correctOccurrence;
cfoValid=correctJointSS;
freqInfo=sixgr.util.structGet(receiver,"Sync.FreqInfo",struct());
sssInfo=sixgr.util.structGet(receiver,"Sync.SSSInfo",struct());
nRx=double(cfg.mimo.num_rx_antennas);
sssHypotheses=double(sixgr.util.structGet(sssInfo,"SearchSpaceSize",0));
sssRE=numel(nrSSSIndices);
peakSoftBufferBytes=16*(numel(received)+numel(receiver.RxSSBGrid))+ ...
    8*numel(sixgr.util.structGet(receiver,"PBCH.EstimatedChannelGrid",[]));

row = struct( ...
    "ScenarioID",string(cfg.meta.scenario_id), ...
    "RunMode",upper(string(cfg.run.mode)), ...
    "SNRDB",double(snrDB), ...
    "Trial",double(trialIndex), ...
    "ChannelSeed",double(channelSeed), ...
    "CFOSeed",double(cfoSeed), ...
    "NoiseSeed",double(noiseSeed), ...
    "TimingSeed",double(timingSeed), ...
    "AppliedCFOHz",double(cfo.AppliedCFOHz), ...
    "UEOscillatorHz",double(cfo.UEOscillatorHz), ...
    "TRPOscillatorHz",double(cfo.TRPOscillatorHz), ...
    "CoarseCFOEstimateHz",double(sixgr.util.structGet( ...
        receiver,"Sync.FreqInfo.CoarseCFOEstimateHz",NaN)), ...
    "FineCFOEstimateHz",double(sixgr.util.structGet( ...
        receiver,"Sync.FreqInfo.FineCFOEstimateHz",NaN)), ...
    "EstimatedCFOHz",double(receiver.CFOEstimateHz), ...
    "CFOErrorHz",double(receiver.CFOErrorHz), ...
    "ResidualCFOBeforeSSS_Hz",double(receiver.CFOErrorHz), ...
    "ResidualCFOBeforePBCH_Hz",double(receiver.CFOErrorHz), ...
    "AppliedTimingSamples",double(trueTiming), ...
    "EstimatedTimingSamples",double(receiver.TimingEstimateSamples), ...
    "TimingErrorSamples",double(receiver.TimingErrorSamples), ...
    "TrueOccurrence",trueOccurrence, ...
    "DetectedOccurrence",detectedOccurrence, ...
    "CorrectOccurrence",logical(correctOccurrence), ...
    "TimingSuccessToleranceSamples",double(timingTolerance), ...
    "TimingWithinTolerance",timingValid&&abs(double(receiver.TimingErrorSamples))<=timingTolerance, ...
    "TimingValidPopulation",logical(timingValid), ...
    "FineTimingErrorSamples",localConditionalValue(receiver.TimingErrorSamples,timingValid), ...
    "FineTimingErrorMicroseconds",1e6*localConditionalValue( ...
        receiver.TimingErrorSamples,timingValid)/bundle.SampleRateHz, ...
    "CFOValidPopulation",logical(cfoValid), ...
    "ConditionalResidualCFOHz",localConditionalValue(receiver.CFOErrorHz,cfoValid), ...
    "RequestedInputSNRDB",double(snrDB), ...
    "MeasuredInputSNRDB",double(measuredSNRDB), ...
    "PSSMetric",double(receiver.PSSMetric), ...
    "TruePSSNID2",double(bundle.NID2), ...
    "EstimatedPSSNID2",double(sixgr.util.structGet(receiver,"Sync.NID2",NaN)), ...
    "TruePCI",double(bundle.NCellID), ...
    "EstimatedPCI",double(sixgr.util.structGet(receiver,"Sync.NCellID",NaN)), ...
    "PSSDetected",logical(receiver.PSSDetected), ...
    "CellDeclared",logical(receiver.CellDeclared), ...
    "NoCellDeclared",logical(receiver.NoCellDeclared), ...
    "CorrectPCIDeclared",logical(receiver.CorrectPCIDeclared), ...
    "WrongPCIDeclared",logical(receiver.WrongPCIDeclared), ...
    "PSSIdentityCorrect",logical(receiver.PSSIdentityCorrect), ...
    "SSSCorrect",logical(receiver.SSSCorrect), ...
    "SSSStagePassed",logical(receiver.Declaration.SSSStagePassed), ...
    "ConditionalSSSEligible",logical(conditionalSSSEligible), ...
    "ConditionalSSSSuccess",logical(conditionalSSSSuccess), ...
    "WrongPCI",logical(receiver.WrongPCI), ...
    "PBCHAttempted",logical(receiver.PBCHAttempted), ...
    "PBCHOk",logical(receiver.PBCHOk), ...
    "PBCHConditionalAttempted",logical(receiver.PBCHAttempted), ...
    "PBCHConditionalOk",logical(receiver.PBCHOk), ...
    "PBCHComponentAttempted",logical(componentPBCH.Attempted), ...
    "PBCHComponentOk",logical(componentPBCH.Ok), ...
    "CompleteSSBSuccess",logical(receiver.CompleteSSBSuccess), ...
    "OracleCompleteSSBSuccess",logical(oracle.CompleteSSBSuccess), ...
    "PBCHBitErrors",double(receiver.PBCH.BitErrors), ...
    "PBCHNoiseVariance",double(receiver.PBCH.NoiseVariance), ...
    "PBCHReceiverSINRDB",double(receiver.PBCH.ReceiverSINRDB), ...
    "PBCHPostEqSINRDB",double(receiver.PBCH.PostEqSINRDB), ...
    "TrueDMRSHypothesis",double(bundle.IBarSSB), ...
    "EstimatedDMRSHypothesis",double(sixgr.util.structGet( ...
        receiver,"PBCH.SelectedIBarSSB",NaN)), ...
    "ChannelEstimateNMSE",double(channelMSE), ...
    "ChannelEstimateNMSEDB",double(channelMSEMeta.NMSEDB), ...
    "ChannelEstimateSquaredError",double(channelMSEMeta.SquaredErrorNumerator), ...
    "ChannelEstimateTruthEnergy",double(channelMSEMeta.TruthEnergyDenominator), ...
    "ChannelEstimateMSEAvailable",logical(channelMSEMeta.Available), ...
    "SearchHypotheses",double(receiver.SearchHypotheses), ...
    "RasterPoints",double(numel(cfg.search.raster_offset_hypotheses)), ...
    "InputTimeSamplesSearched",double(sixgr.util.structGet(freqInfo,"SearchSamples",0)), ...
    "TimingLagsEvaluated",double(sixgr.util.structGet(freqInfo,"TimingLagsEvaluated",0)), ...
    "CoarseCFOHypotheses",double(numel(cfg.search.cfo_hypotheses_hz)), ...
    "FineCFOHypotheses",double(logical(sixgr.util.structGet(freqInfo,"FineCFO.Available",false))), ...
    "PSSSequences",double(sixgr.util.structGet(freqInfo,"PSSSequences",0)), ...
    "PSSCorrelationVectors",double(sixgr.util.structGet(freqInfo,"PSSCorrelationVectors",0)), ...
    "PSSComplexMultiplications",double(sixgr.util.structGet(freqInfo,"PSSComplexMultiplications",0)), ...
    "PSSComplexAdditions",double(sixgr.util.structGet(freqInfo,"PSSComplexAdditions",0)), ...
    "FFTCount",double(sixgr.util.structGet(freqInfo,"FFTCount",0)), ...
    "SSSSequenceHypotheses",sssHypotheses, ...
    "SSSComplexMultiplications",sssHypotheses*sssRE*nRx, ...
    "SSSComplexAdditions",sssHypotheses*max(sssRE-1,0)*nRx, ...
    "DMRSHypothesesTested",double(receiver.PBCH.DMRSHypothesesTested), ...
    "ChannelEstimationOperations",double(receiver.PBCH.DMRSHypothesesTested)* ...
        (numel(nrPBCHDMRSIndices(bundle.NCellID))+sssRE)*nRx, ...
    "PBCHDemaps",double(receiver.PBCH.PolarDecodes), ...
    "PolarDecodes",double(receiver.PBCH.PolarDecodes), ...
    "PeakSoftBufferBytes",double(peakSoftBufferBytes), ...
    "BufferTimeProductByteSamples",double(peakSoftBufferBytes*size(received,1)), ...
    "RFActiveSamples",double(size(received,1)*nRx), ...
    "RFActiveTimeSeconds",double(size(received,1)/bundle.SampleRateHz), ...
    "PSSStageThreshold",double(thresholds.PSSStageThreshold), ...
    "FalseAlarmThreshold",double(thresholds.GlobalDeclarationThreshold), ...
    "JointDeclarationStatistic",double(receiver.Declaration.JointDeclarationStatistic), ...
    "SSSNormalizedMetric",double(receiver.Declaration.SSSNormalizedMetric), ...
    "SSSNormalizedMetricMargin",double(receiver.Declaration.SSSNormalizedMetricMargin), ...
    "ChannelBackend",string(channel.ExecutionBackend), ...
    "NoiseCalibrationSource",string(noiseMeta.CalibrationSource), ...
    "EvidenceClass","actual_nr_ssb_waveform_receiver_truth", ...
    "ApproximationMode","none", ...
    "FailureReason",string(receiver.FailureReason));
row.PBCHComponentFailureReason = string(componentPBCH.FailureReason);
row.FailureStage = localFailureStage(receiver,channelMSEMeta,correctOccurrence);
end

function value=localConditionalValue(raw,condition)
if condition
    value=double(raw);
else
    value=NaN;
end
end

function stage=localFailureStage(receiver,channelMeta,correctOccurrence)
if ~receiver.PSSDetected
    stage="FAIL_PSS_THRESHOLD";
elseif ~correctOccurrence
    stage="FAIL_PSS_WRONG_TIMING";
elseif ~receiver.PSSIdentityCorrect
    stage="FAIL_PSS_WRONG_SEQUENCE";
elseif ~receiver.CellDeclared
    stage="FAIL_SSS";
elseif receiver.WrongPCIDeclared
    stage="FAIL_WRONG_PCI";
elseif receiver.PBCHAttempted && ~channelMeta.Available
    if contains(string(channelMeta.Reason),"dmrs")
        stage="FAIL_DMRS";
    else
        stage="FAIL_CHANNEL_ESTIMATION";
    end
elseif receiver.PBCHAttempted && ~receiver.PBCHOk
    stage="FAIL_PBCH_CRC";
else
    stage="SUCCESS";
end
end
