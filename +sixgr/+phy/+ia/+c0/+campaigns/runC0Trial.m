function row = runC0Trial(bundle,cfg,snrDB,trialIndex,threshold)
%RUNC0TRIAL Execute one production IA end-to-end C0 realization.
seedBase = double(cfg.run.seed_set_main)+100000*find(double(cfg.snr.coarse_grid_db)==snrDB,1)+trialIndex;
if isempty(seedBase) || ~isfinite(seedBase)
    seedBase = double(cfg.run.seed_set_main)+1000000+trialIndex+round(100*snrDB);
end
channelSeed = seedBase+11;
cfoSeed = seedBase+23;
noiseSeed = seedBase+37;
timingSeed = seedBase+47;

channel = sixgr.phy.ia.c0.channel.applyFading( ...
    bundle.Waveform,bundle,cfg,channelSeed);
old = rng;
cleanup = onCleanup(@()rng(old)); %#ok<NASGU>
rng(timingSeed,"twister");
timingBudget = double(cfg.search.timing_uncertainty_samples);
channelTiming = double(channel.TimingOffsetSamples);
remainingTimingBudget = floor(timingBudget-channelTiming);
if remainingTimingBudget < 0
    error("sixgr:phy:ia:c0:campaign:ChannelDelayOutsideTimingBudget", ...
        "The physical channel timing offset (%g samples) exceeds the configured total timing uncertainty (%g samples). Increase search.timing_uncertainty_samples in YAML.", ...
        channelTiming,timingBudget);
end
% search.timing_uncertainty_samples is the total receiver uncertainty,
% including the physical fading-channel delay. Do not add an independent
% random delay on top of that budget.
timingPad = randi([0 remainingTimingBudget]);
cleanNoCFO = [complex(zeros(timingPad,size(channel.Waveform,2)));channel.Waveform];
cfgRuntime = cfg;
cfgRuntime.runtime = struct("sample_rate_hz",bundle.SampleRateHz);
[cleanWithCFO,cfo] = sixgr.phy.ia.c0.impairments.applyOscillatorCFO( ...
    cleanNoCFO,cfgRuntime,cfoSeed);
measurementStart = timingPad+channelTiming;
[signalREPower,~] = sixgr.phy.ia.c0.channel.measureActiveREPower( ...
    cleanNoCFO,bundle,measurementStart);
[received,noise,noiseMeta] = sixgr.phy.ia.c0.channel.addNoiseForTargetSNR( ...
    cleanWithCFO,bundle,signalREPower,snrDB,noiseSeed);
[noiseREPower,~] = sixgr.phy.ia.c0.channel.measureActiveREPower( ...
    noise,bundle,measurementStart);
measuredSNRDB = 10*log10(signalREPower/max(noiseREPower,realmin));
symbolLengths = double(bundle.OFDMInfo.SymbolLengths(:));
pssPrefix = sum(symbolLengths(1:double(bundle.CandidateStartSymbol)));
trueTiming = measurementStart+pssPrefix;
receiver = sixgr.phy.ia.c0.receiver.runCompleteSSBReceiver( ...
    received,bundle,cfg,threshold, ...
    "TrueCFOHz",cfo.AppliedCFOHz,"TrueTimingSamples",trueTiming);
oracle = sixgr.phy.ia.c0.receiver.runOracleReceiver( ...
    received,bundle,cfg,cfo.AppliedCFOHz,trueTiming);
[channelMSE,channelMSEMeta] = sixgr.phy.ia.c0.receiver.channelEstimateMSE( ...
    receiver,channel,bundle,cfg);

row = struct( ...
    "ScenarioID",string(cfg.meta.scenario_id), ...
    "RunMode",string(cfg.run.mode), ...
    "SNRDB",double(snrDB), ...
    "Trial",double(trialIndex), ...
    "ChannelSeed",double(channelSeed), ...
    "CFOSeed",double(cfoSeed), ...
    "NoiseSeed",double(noiseSeed), ...
    "TimingSeed",double(timingSeed), ...
    "AppliedCFOHz",double(cfo.AppliedCFOHz), ...
    "EstimatedCFOHz",double(receiver.CFOEstimateHz), ...
    "CFOErrorHz",double(receiver.CFOErrorHz), ...
    "AppliedTimingSamples",double(trueTiming), ...
    "EstimatedTimingSamples",double(receiver.TimingEstimateSamples), ...
    "TimingErrorSamples",double(receiver.TimingErrorSamples), ...
    "RequestedInputSNRDB",double(snrDB), ...
    "MeasuredInputSNRDB",double(measuredSNRDB), ...
    "PSSMetric",double(receiver.PSSMetric), ...
    "PSSDetected",logical(receiver.PSSDetected), ...
    "PSSIdentityCorrect",logical(receiver.PSSIdentityCorrect), ...
    "SSSCorrect",logical(receiver.SSSCorrect), ...
    "WrongPCI",logical(receiver.WrongPCI), ...
    "PBCHAttempted",logical(receiver.PBCHAttempted), ...
    "PBCHOk",logical(receiver.PBCHOk), ...
    "CompleteSSBSuccess",logical(receiver.CompleteSSBSuccess), ...
    "OracleCompleteSSBSuccess",logical(oracle.CompleteSSBSuccess), ...
    "PBCHBitErrors",double(receiver.PBCH.BitErrors), ...
    "PBCHNoiseVariance",double(receiver.PBCH.NoiseVariance), ...
    "PBCHReceiverSINRDB",double(receiver.PBCH.ReceiverSINRDB), ...
    "PBCHPostEqSINRDB",double(receiver.PBCH.PostEqSINRDB), ...
    "ChannelEstimateNMSE",double(channelMSE), ...
    "ChannelEstimateMSEAvailable",logical(channelMSEMeta.Available), ...
    "SearchHypotheses",double(receiver.SearchHypotheses), ...
    "DMRSHypothesesTested",double(receiver.PBCH.DMRSHypothesesTested), ...
    "PolarDecodes",double(receiver.PBCH.PolarDecodes), ...
    "FalseAlarmThreshold",double(threshold), ...
    "ChannelBackend",string(channel.ExecutionBackend), ...
    "NoiseCalibrationSource",string(noiseMeta.CalibrationSource), ...
    "EvidenceClass","actual_nr_ssb_waveform_receiver_truth", ...
    "ApproximationMode","none", ...
    "FailureReason",string(receiver.FailureReason));
end
