function result = runC0(configPath,runMode,varargin)
%RUNC0 Execute Phase-1 C0 in the production initial-access namespace.
p=inputParser;
p.addParameter("OutputRoot","",@(x)ischar(x)||isstring(x));
p.addParameter("RunId","",@(x)ischar(x)||isstring(x));
p.parse(varargin{:});
[cfg,configMeta]=sixgr.phy.ia.c0.config.loadScenario( ...
    string(configPath),string(runMode));
bundle=sixgr.phy.ia.c0.waveform.buildNRAnchorA(cfg);
cfg.runtime=struct("sample_rate_hz",bundle.SampleRateHz);

outputRoot=string(p.Results.OutputRoot);
if strlength(outputRoot)==0, outputRoot=string(cfg.output.root); end
runId=string(p.Results.RunId);
if strlength(runId)==0
    runId="C0_"+string(cfg.run.mode)+"_"+string(datetime("now","Format","yyyyMMdd_HHmmss"));
end
if ~any(strcmpi(string(cfg.run.mode),["tdoc" "exhaustive"])) && ...
        contains(lower(runId),"tdoc")
    error("sixgr:phy:ia:c0:campaign:MisleadingRunId", ...
        "A non-TDOC C0 run ID must not contain 'tdoc'; resolved run.mode is %s.", ...
        upper(string(cfg.run.mode)));
end
runFolder=fullfile(char(outputRoot),char(runId));
if isfolder(runFolder) || isfile(runFolder)
    error("sixgr:phy:ia:c0:campaign:OutputExists", ...
        "Refusing to overwrite C0 output: %s.",runFolder);
end
mkdir(runFolder); mkdir(fullfile(runFolder,"figures")); mkdir(fullfile(runFolder,"logs"));
sixgr.lls6g.config.writeYAML(fullfile(runFolder,"config_resolved.yaml"),cfg);
for k=1:numel(configMeta.SourceFiles)
    copyfile(configMeta.SourceFiles(k),fullfile(runFolder,sprintf("config_source_%02d.yaml",k)));
end

ceUnitTests=sixgr.phy.ia.c0.validation.runPBCHCEUnitTests(bundle,cfg);
writetable(ceUnitTests,fullfile(runFolder,"C0_ce_unit_tests.csv"));
if ~all(ceUnitTests.Pass)
    error("sixgr:phy:ia:c0:validation:PBCHCEUnitTest", ...
        "C0 execution is blocked because PBCH CE unit tests did not all pass.");
end
snrCalibration=sixgr.phy.ia.c0.validation.runSNRCalibration(bundle,cfg);
writetable(snrCalibration,fullfile(runFolder,"C0_snr_calibration.csv"));
if ~all(snrCalibration.Pass)
    error("sixgr:phy:ia:c0:validation:SNRCalibration", ...
        "C0 execution is blocked because requested/actual active-RE SNR differs by more than the configured tolerance.");
end

fprintf('C0 %s: calibrating global false alarm with %d independent noise windows...\n', ...
    cfg.run.mode,cfg.false_alarm.calibration_trials);
calibration=sixgr.phy.ia.c0.search.calibrateGlobalFalseAlarm(bundle,cfg, ...
    "CheckpointPath",fullfile(runFolder,"false_alarm_calibration_checkpoint.mat"), ...
    "ProgressCSVPath",fullfile(runFolder,"false_alarm_calibration_progress.csv"));
faValidation=sixgr.phy.ia.c0.search.validateGlobalFalseAlarm( ...
    bundle,cfg,calibration, ...
    "CheckpointPath",fullfile(runFolder,"false_alarm_validation_checkpoint.mat"), ...
    "ProgressCSVPath",fullfile(runFolder,"false_alarm_validation_progress.csv"));
localWriteFalseAlarm(runFolder,calibration,faValidation);

snrGrid=sixgr.phy.ia.c0.util.initialSNRGrid(cfg);
raw=table();
for snr=snrGrid
    [raw,newRows]=localRunPoint(raw,bundle,cfg,snr,calibration.Thresholds,runFolder);
    fprintf('[C0][%s][A20RB4][%s][practical][%+.2fdB] trials=%d complete_errors=%d status=SIMULATED\n', ...
        configMeta.ConfigHash,cfg.waveform.normalization,snr,height(newRows),nnz(~newRows.CompleteSSBSuccess));
end
points=localAggregate(raw,cfg);

if any(strcmpi(string(cfg.run.mode),["tdoc" "exhaustive"]))
    [raw,points]=localExtendAndRefine(raw,points,bundle,cfg,calibration.Thresholds,runFolder);
end
crossings=sixgr.phy.ia.c0.metrics.buildCrossingTable(points,cfg);
writetable(raw,fullfile(runFolder,"raw_trials.csv"));
writetable(points,fullfile(runFolder,"points.csv"));
writetable(crossings,fullfile(runFolder,"target_crossings.csv"));
artifactTables=sixgr.phy.ia.c0.report.writeC0Artifacts( ...
    runFolder,cfg,raw,points,crossings,calibration,faValidation);
save(fullfile(runFolder,"raw.mat"),"raw","points","crossings","calibration","faValidation","cfg","configMeta","-v7.3");

resource=table(string(bundle.ResourceAudit.Candidate),bundle.ResourceAudit.PSSRE, ...
    bundle.ResourceAudit.SSSRE,bundle.ResourceAudit.PBCHRE,bundle.ResourceAudit.DMRSRE, ...
    bundle.ResourceAudit.ActiveRE,bundle.ResourceAudit.ReservedUnusedRE, ...
    bundle.ResourceAudit.TotalEnergy,bundle.ResourceAudit.MeanActiveREEPRE, ...
    string(cfg.waveform.normalization),bundle.ResourceAudit.Normalization.Scale, ...
    bundle.ResourceAudit.Normalization.ClosureDB,string(bundle.ResourceAudit.ResourceMapSHA256), ...
    'VariableNames',{'Candidate','PSSRE','SSSRE','PBCHRE','DMRSRE','ActiveRE', ...
    'UnusedRE','TotalEnergy','MeanActiveREEPRE','Normalization','Scale','ClosureDB','ResourceMapSHA256'});
writetable(resource,fullfile(runFolder,"resource_audit.csv"));

zeroCfg=cfg;
zeroCfg.channel.model="AWGN"; zeroCfg.channel.delay_profile="AWGN";
zeroCfg.oscillator.ue_ppm_range=[0 0]; zeroCfg.oscillator.trp_ppm_range=[0 0];
zeroCfg.search.cfo_hypotheses_hz=0; zeroCfg.search.timing_uncertainty_samples=0;
zeroAnchor=sixgr.phy.ia.c0.campaigns.runC0Trial( ...
    bundle,zeroCfg,35,999001,calibration.Thresholds);
writetable(struct2table(zeroAnchor,"AsArray",true),fullfile(runFolder,"zero_impairment_anchor.csv"));

lineage=sixgr.phy.ia.c0.plots.renderC0Figures( ...
    runFolder,cfg,calibration,faValidation,raw,points,crossings);
writetable(lineage,fullfile(runFolder,"figure_lineage.csv"));
[gates,summary]=sixgr.phy.ia.c0.validation.validateC0( ...
    cfg,bundle,calibration,faValidation, ...
    raw,points,crossings,zeroAnchor,lineage,ceUnitTests,snrCalibration);
writetable(gates,fullfile(runFolder,"truth_contract.csv"));
verification=sixgr.phy.ia.c0.util.verifyFigureLineage(runFolder,lineage);
writetable(verification,fullfile(runFolder,"artifact_verification.csv"));
manifest=sixgr.phy.ia.c0.util.buildManifest( ...
    cfg,configMeta,runFolder,height(raw),height(lineage));
manifest.SmokeOrEngineeringPass=logical(summary.SmokeOrEngineeringPass);
manifest.TDocPass=logical(summary.TDocPass);
manifest.TruthGatesPassed=double(summary.PassedApplicableGates);
manifest.TruthGatesApplicable=double(summary.ApplicableGateCount);
manifest.ArtifactVerificationPassed=all(verification.Pass);
manifest.GlobalFalseAlarmValidationPassed=logical(faValidation.Passed);
sixgr.util.writeTextFile(fullfile(runFolder,"manifest.json"), ...
    jsonencode(manifest,"PrettyPrint",true),"MimeType","application/json");
sixgr.phy.ia.c0.util.writeC0Report( ...
    runFolder,cfg,summary,faValidation,points,crossings);

result=struct("RunFolder",string(runFolder),"Config",cfg,"Bundle",bundle, ...
    "Calibration",calibration,"FalseAlarmValidation",faValidation, ...
    "CEUnitTests",ceUnitTests,"SNRCalibration",snrCalibration, ...
    "RawTrials",raw,"Points",points,"Crossings",crossings,"TruthGates",gates, ...
    "ArtifactTables",artifactTables, ...
    "ArtifactVerification",verification,"Manifest",manifest, ...
    "Passed",logical(summary.SmokeOrEngineeringPass)&&all(verification.Pass), ...
    "TDocPass",logical(summary.TDocPass)&&all(verification.Pass));
end

function [raw,newRows]=localRunPoint(raw,bundle,cfg,snr,thresholds,runFolder)
maxTrials=double(cfg.run.max_trials_per_snr); minErrors=double(cfg.run.min_errors_per_snr);
rows=cell(maxTrials,1); jointErrors=0; pbchErrors=0; completeErrors=0; n=0;
for trial=1:maxTrials
    n=n+1; rows{n}=sixgr.phy.ia.c0.campaigns.runC0Trial( ...
        bundle,cfg,snr,trial,thresholds);
    localAssertTrialInvariants(rows{n});
    jointErrors=jointErrors+~(rows{n}.CellDeclared&&rows{n}.PSSIdentityCorrect&&rows{n}.SSSCorrect);
    pbchErrors=pbchErrors+(rows{n}.PBCHComponentAttempted&&~rows{n}.PBCHComponentOk);
    completeErrors=completeErrors+~rows{n}.CompleteSSBSuccess;
    if mod(trial,double(cfg.run.checkpoint_interval))==0
        partial=struct2table(vertcat(rows{1:n}),"AsArray",true);
        checkpoint=[raw;partial];
        save(fullfile(runFolder,"checkpoint.mat"),"checkpoint","-v7.3");
        localWriteWaveformProgress(runFolder,snr,trial,maxTrials,minErrors, ...
            jointErrors,pbchErrors,completeErrors,rows{n},"RUNNING");
        fprintf('[C0][%s][WAVEFORM][%+.2fdB] completed=%d/%d (%.3f%% max) joint_errors=%d pbch_component_errors=%d complete_errors=%d\n', ...
            upper(string(cfg.run.mode)),snr,trial,maxTrials,100*trial/maxTrials, ...
            jointErrors,pbchErrors,completeErrors);
    end
    if trial>=1 && jointErrors>=minErrors && pbchErrors>=minErrors && completeErrors>=minErrors
        break;
    end
end
newRows=struct2table(vertcat(rows{1:n}),"AsArray",true);
raw=[raw;newRows];
writetable(raw,fullfile(runFolder,"raw_trials_checkpoint.csv"));
localWriteWaveformProgress(runFolder,snr,n,maxTrials,minErrors, ...
    jointErrors,pbchErrors,completeErrors,rows{n},"COMPLETE");
end

function localWriteWaveformProgress(folder,snr,trials,maxTrials,minErrors, ...
        jointErrors,pbchErrors,completeErrors,lastRow,status)
token=replace(replace(sprintf('%+.2f',snr),'+','p'),'-','m');
token=replace(token,'.','p');
path=fullfile(folder,"logs","snr_"+string(token)+"_progress.csv");
progress=table(snr,string(status),trials,maxTrials,100*trials/maxTrials, ...
    jointErrors,pbchErrors,completeErrors,minErrors, ...
    jointErrors>=minErrors||trials>=maxTrials, ...
    pbchErrors>=minErrors||trials>=maxTrials, ...
    completeErrors>=minErrors||trials>=maxTrials, ...
    double(lastRow.ChannelSeed),double(lastRow.CFOSeed), ...
    double(lastRow.NoiseSeed),double(lastRow.TimingSeed), ...
    string(datetime("now","TimeZone","UTC", ...
        "Format","yyyy-MM-dd'T'HH:mm:ss.SSSXXX")), ...
    'VariableNames',{'SNRDB','Status','CompletedTrials','MaximumTrials', ...
    'PercentOfMaximum','JointSSErrors','PBCHComponentErrors', ...
    'CompleteSSBErrors','MinimumErrors','JointSSStoppingQualified', ...
    'PBCHComponentStoppingQualified','CompleteSSBStoppingQualified', ...
    'LastChannelSeed','LastCFOSeed','LastNoiseSeed','LastTimingSeed', ...
    'UpdatedUTC'});
writetable(progress,path);
end

function localAssertTrialInvariants(row)
declarations=double(row.NoCellDeclared)+double(row.CorrectPCIDeclared)+ ...
    double(row.WrongPCIDeclared);
if declarations~=1
    error("sixgr:phy:ia:c0:accounting:DeclarationPartition", ...
        "No/correct/wrong PCI declaration states must be mutually exclusive and exhaustive.");
end
joint=logical(row.CellDeclared)&&logical(row.PSSIdentityCorrect)&&logical(row.SSSCorrect);
pssEligible=logical(row.ConditionalSSSEligible);
sssSuccess=logical(row.ConditionalSSSSuccess);
sssError=pssEligible&&~sssSuccess;
if double(sssSuccess)+double(sssError)~=double(pssEligible)
    error("sixgr:phy:ia:c0:accounting:ConditionalSSS", ...
        "Conditional SSS success/error states must partition PSS-eligible trials.");
end
if logical(row.PBCHConditionalAttempted)~=joint
    error("sixgr:phy:ia:c0:accounting:ConditionalPBCH", ...
        "Conditional PBCH attempts must equal correct joint PSS/SSS declarations.");
end
if logical(row.CompleteSSBSuccess)&&~joint
    error("sixgr:phy:ia:c0:accounting:CompleteWithoutJointSS", ...
        "Complete SSB success cannot occur without correct joint PSS/SSS acquisition.");
end
if ~logical(row.PBCHComponentAttempted)
    error("sixgr:phy:ia:c0:accounting:MissingComponentPBCH", ...
        "Every C0 channel realization must enter the PBCH component receiver.");
end
end

function points=localAggregate(raw,cfg)
points=sixgr.phy.ia.c0.metrics.aggregatePoints(raw,cfg);
end

function [raw,points]=localExtendAndRefine(raw,points,bundle,cfg,threshold,runFolder)
while true
    c=sixgr.phy.ia.c0.metrics.buildCrossingTable(points,cfg);
    componentRows=startsWith(c.Label,"gamma_SS_")|startsWith(c.Label,"gamma_PBCH_");
    missing=c(componentRows&~c.Bracketed,:); next=[];
    for k=1:height(missing)
        values=points.(char(missing.Metric(k))); target=missing.Target(k);
        if all(values>target) && max(points.SNRDB)<double(cfg.snr.maximum_db)
            next=max(points.SNRDB)+double(cfg.snr.extension_step_db); break;
        elseif all(values<target) && min(points.SNRDB)>double(cfg.snr.minimum_db)
            next=min(points.SNRDB)-double(cfg.snr.extension_step_db); break;
        end
    end
    if isempty(next), break; end
    [raw,~]=localRunPoint(raw,bundle,cfg,next,threshold,runFolder); points=localAggregate(raw,cfg);
end
c=sixgr.phy.ia.c0.metrics.buildCrossingTable(points,cfg); refined=[];
for k=1:height(c)
    if c.Bracketed(k) && isfinite(c.CrossingSNRDB(k)) && ...
            (startsWith(c.Label(k),"gamma_SS_")||startsWith(c.Label(k),"gamma_PBCH_"))
        refined=[refined sixgr.phy.ia.c0.util.refinementSNRGrid( ...
            cfg,double(c.CrossingSNRDB(k)))]; %#ok<AGROW>
    end
end
refined=refined(refined>=double(cfg.snr.minimum_db)&refined<=double(cfg.snr.maximum_db));
refined=setdiff(unique(round(refined,10)),points.SNRDB);
for snr=refined
    [raw,~]=localRunPoint(raw,bundle,cfg,snr,threshold,runFolder);
end
points=localAggregate(raw,cfg);
end

function localWriteFalseAlarm(folder,cal,val)
T=table((1:cal.TrialCount)',cal.Seeds,cal.PSSMetrics,cal.SSSMetrics, ...
    cal.JointMetricsBeforePSSStage,cal.Metrics, ...
    repmat(cal.PSSStageThreshold,cal.TrialCount,1), ...
    repmat(cal.Threshold,cal.TrialCount,1),cal.Metrics>=cal.Threshold, ...
    'VariableNames',{'Trial','Seed','PSSStatistic','SSSNormalizedStatistic', ...
    'JointStatisticBeforePSSStage','FinalDeclarationStatistic', ...
    'PSSStageThreshold','GlobalDeclarationThreshold','Exceeded'});
writetable(T,fullfile(folder,"false_alarm_calibration.csv"));
V=table((1:val.TrialCount)',val.Seeds,val.Metrics, ...
    repmat(val.PSSStageThreshold,val.TrialCount,1), ...
    repmat(val.Threshold,val.TrialCount,1),val.Declared, ...
    'VariableNames',{'Trial','Seed','JointDeclarationStatistic', ...
    'PSSStageThreshold','GlobalDeclarationThreshold','FalseAlarm'});
writetable(V,fullfile(folder,"false_alarm_validation.csv"));
S=table(cal.TrialCount,val.TrialCount,cal.SeedFirst,cal.SeedLast, ...
    val.SeedFirst,val.SeedLast,val.IndependentFromCalibration, ...
    cal.ReceiverExceptionCount,val.ReceiverExceptionCount, ...
    cal.ThresholdOrderStatisticIndex, ...
    cal.PSSStageThreshold,cal.Threshold,val.FalseAlarms,val.EmpiricalPFA, ...
    val.CILow,val.CIHigh,val.RelativeCIHalfWidth,val.TargetPFA, ...
    val.TargetInsideCI,val.CIPrecisionPassed,val.Passed, ...
    'VariableNames',{'CalibrationTrials','ValidationTrials', ...
    'CalibrationSeedFirst','CalibrationSeedLast','ValidationSeedFirst', ...
    'ValidationSeedLast','IndependentSeedRanges', ...
    'CalibrationReceiverExceptions','ValidationReceiverExceptions', ...
    'ThresholdOrderStatisticIndex','PSSStageThreshold', ...
    'GlobalDeclarationThreshold','FalseAlarms','EmpiricalPFA','CILow', ...
    'CIHigh','RelativeCIHalfWidth','TargetPFA','TargetInsideCI', ...
    'CIPrecisionPassed','Passed'});
writetable(S,fullfile(folder,"false_alarm_summary.csv"));
end
