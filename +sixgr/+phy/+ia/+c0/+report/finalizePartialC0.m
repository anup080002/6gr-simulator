function result = finalizePartialC0(sourceRunFolder,varargin)
%FINALIZEPARTIALC0 Publish stopped C0 evidence without claiming completion.
% Only rows persisted in the atomic waveform checkpoint are used. Missing
% SNR points are never synthesized, and the normal C0 truth validator is
% deliberately not called for an incomplete campaign.
arguments
    sourceRunFolder (1,1) string
end
arguments (Repeating)
    varargin
end
p=inputParser;
p.addParameter("OutputFolder","",@(x)ischar(x)||isstring(x));
p.parse(varargin{:});
sourceRunFolder=string(java.io.File(sourceRunFolder).getCanonicalPath());
if ~isfolder(sourceRunFolder)
    error("sixgr:phy:ia:c0:partial:SourceMissing", ...
        "Stopped C0 source run does not exist: %s.",sourceRunFolder);
end
required=["checkpoint.mat" "config_resolved.yaml" ...
    "false_alarm_calibration.csv" "false_alarm_validation.csv" ...
    "false_alarm_summary.csv"];
for name=required
    if ~isfile(fullfile(sourceRunFolder,name))
        error("sixgr:phy:ia:c0:partial:EvidenceMissing", ...
            "Partial finalization requires persisted source %s.", ...
            fullfile(sourceRunFolder,name));
    end
end
outputFolder=string(p.Results.OutputFolder);
if strlength(outputFolder)==0
    outputFolder=fullfile(sourceRunFolder,"partial_finalization");
end
if isfolder(outputFolder)||isfile(outputFolder)
    error("sixgr:phy:ia:c0:partial:OutputExists", ...
        "Refusing to overwrite partial finalization output: %s.",outputFolder);
end
mkdir(outputFolder); mkdir(fullfile(outputFolder,"figures"));

cfg=sixgr.lls6g.config.readConfigFile( ...
    fullfile(sourceRunFolder,"config_resolved.yaml"));
sixgr.phy.ia.c0.config.validateScenario(cfg);
saved=load(fullfile(sourceRunFolder,"checkpoint.mat"),"checkpoint");
if ~isfield(saved,"checkpoint")||~istable(saved.checkpoint)||isempty(saved.checkpoint)
    error("sixgr:phy:ia:c0:partial:BadCheckpoint", ...
        "C0 waveform checkpoint contains no actual trial table.");
end
raw=saved.checkpoint;
points=sixgr.phy.ia.c0.metrics.aggregatePoints(raw,cfg);
crossings=sixgr.phy.ia.c0.metrics.buildCrossingTable(points,cfg);
[calibration,validation]=localFalseAlarm(sourceRunFolder,cfg);

writetable(raw,fullfile(outputFolder,"raw_trials_partial.csv"));
writetable(points,fullfile(outputFolder,"points_partial.csv"));
writetable(crossings,fullfile(outputFolder,"target_crossings_partial.csv"));
copyfile(fullfile(sourceRunFolder,"config_resolved.yaml"), ...
    fullfile(outputFolder,"config_resolved.yaml"));
copyfile(fullfile(sourceRunFolder,"false_alarm_calibration.csv"), ...
    fullfile(outputFolder,"false_alarm_calibration.csv"));
copyfile(fullfile(sourceRunFolder,"false_alarm_validation.csv"), ...
    fullfile(outputFolder,"false_alarm_validation.csv"));
copyfile(fullfile(sourceRunFolder,"false_alarm_summary.csv"), ...
    fullfile(outputFolder,"false_alarm_summary_source.csv"));
artifacts=sixgr.phy.ia.c0.report.writeC0Artifacts( ...
    outputFolder,cfg,raw,points,crossings,calibration,validation);
completion=repmat("PARTIAL_STOPPED_BY_USER",height(artifacts.Summary),1);
artifacts.Summary.CompletionState=completion;
writetable(artifacts.Summary,fullfile(outputFolder,"C0_summary.csv"));
artifacts.FalseAlarm.CompletionState=repmat( ...
    "PARTIAL_STOPPED_BY_USER",height(artifacts.FalseAlarm),1);
writetable(artifacts.FalseAlarm,fullfile(outputFolder,"C0_false_alarm.csv"));

lineage=sixgr.phy.ia.c0.plots.renderC0Figures( ...
    outputFolder,cfg,calibration,validation,raw,points,crossings, ...
    "CompletionState","PARTIAL_STOPPED_BY_USER");
writetable(lineage,fullfile(outputFolder,"figure_lineage.csv"));
verification=sixgr.phy.ia.c0.util.verifyFigureLineage(outputFolder,lineage);
writetable(verification,fullfile(outputFolder,"artifact_verification.csv"));

planned=sixgr.phy.ia.c0.util.initialSNRGrid(cfg);
actual=unique(points.SNRDB,"sorted").';
completeMask=points.JointSSStoppingQualified& ...
    points.PBCHComponentStoppingQualified&points.CompleteSSBStoppingQualified;
completeSNR=points.SNRDB(completeMask).';
partialSNR=points.SNRDB(~completeMask).';
missingSNR=setdiff(planned,actual,"stable");
declarationPartition=all(double(raw.NoCellDeclared)+ ...
    double(raw.CorrectPCIDeclared)+double(raw.WrongPCIDeclared)==1);
joint=raw.CellDeclared&raw.PSSIdentityCorrect&raw.SSSCorrect;
populationIntegrity=all(raw.CompleteSSBSuccess<=joint)&& ...
    all(raw.PBCHConditionalAttempted==joint)&& ...
    all(raw.PBCHComponentAttempted);
truthRows=all(raw.EvidenceClass=="actual_nr_ssb_waveform_receiver_truth")&& ...
    all(raw.ApproximationMode=="none");
gates=table( ...
    ["checkpoint_has_actual_rows";"calibration_complete"; ...
    "validation_complete";"seed_ranges_independent"; ...
    "receiver_exceptions_zero";"declaration_population_integrity"; ...
    "waveform_truth_rows_only";"all_planned_snr_points_complete"; ...
    "false_alarm_target_inside_ci";"false_alarm_precision"; ...
    "partial_figure_integrity"], ...
    [height(raw)>0;calibration.TrialCount==double(cfg.false_alarm.calibration_trials); ...
    validation.TrialCount==double(cfg.false_alarm.validation_trials); ...
    validation.IndependentFromCalibration; ...
    calibration.ReceiverExceptionCount==0&&validation.ReceiverExceptionCount==0; ...
    declarationPartition&&populationIntegrity;truthRows; ...
    isempty(partialSNR)&&isempty(missingSNR);validation.TargetInsideCI; ...
    validation.CIPrecisionPassed;all(verification.Pass)], ...
    'VariableNames',{'Check','Pass'});
gates.Status=repmat("PASS",height(gates),1);
gates.Status(~gates.Pass)="FAIL_OR_INCOMPLETE";
writetable(gates,fullfile(outputFolder,"partial_gate_status.csv"));

[~,commit]=system("git rev-parse HEAD");
[dirtyStatus,dirtyText]=system("git status --porcelain");
manifest=struct( ...
    "SchemaVersion","sixgr.phy.ia.c0.partial.v1", ...
    "CompletionState","PARTIAL_STOPPED_BY_USER", ...
    "ClaimClass","PARTIAL_ENGINEERING_NOT_TDOC", ...
    "ScientificCompletionPassed",false, ...
    "ArtifactIntegrityPassed",all(verification.Pass), ...
    "SourceRunFolder",sourceRunFolder, ...
    "OutputFolder",outputFolder, ...
    "SourceCheckpointSHA256",localFileHash( ...
        fullfile(sourceRunFolder,"checkpoint.mat")), ...
    "ResolvedConfigSHA256",localFileHash( ...
        fullfile(sourceRunFolder,"config_resolved.yaml")), ...
    "GitCommit",string(strtrim(commit)), ...
    "GitWorktreeDirty",dirtyStatus~=0||strlength(strtrim(string(dirtyText)))>0, ...
    "RunMode",upper(string(cfg.run.mode)), ...
    "RawTrialCount",height(raw), ...
    "ActualSNRDB",actual,"CompletedSNRDB",completeSNR, ...
    "PartialSNRDB",partialSNR,"MissingPlannedSNRDB",missingSNR, ...
    "CalibrationTrials",calibration.TrialCount, ...
    "ValidationTrials",validation.TrialCount, ...
    "ValidationPFA",validation.EmpiricalPFA, ...
    "ValidationPFACILow",validation.CILow, ...
    "ValidationPFACIHigh",validation.CIHigh, ...
    "ValidationCIPrecisionPassed",validation.CIPrecisionPassed, ...
    "FigureCount",height(lineage), ...
    "GeneratedUTC",string(datetime("now","TimeZone","UTC", ...
        "Format","yyyy-MM-dd'T'HH:mm:ss'Z'")));
sixgr.util.writeTextFile(fullfile(outputFolder,"partial_manifest.json"), ...
    jsonencode(manifest,"PrettyPrint",true),"MimeType","application/json");
localReport(outputFolder,manifest,gates);
save(fullfile(outputFolder,"partial_evidence.mat"), ...
    "raw","points","crossings","calibration","validation", ...
    "lineage","verification","manifest","-v7.3");
result=struct("OutputFolder",outputFolder,"Raw",raw,"Points",points, ...
    "Crossings",crossings,"Lineage",lineage, ...
    "Verification",verification,"Gates",gates,"Manifest",manifest);
end

function [calibration,validation]=localFalseAlarm(folder,cfg)
C=readtable(fullfile(folder,"false_alarm_calibration.csv"), ...
    "TextType","string");
V=readtable(fullfile(folder,"false_alarm_validation.csv"), ...
    "TextType","string");
S=readtable(fullfile(folder,"false_alarm_summary.csv"), ...
    "TextType","string");
if height(S)~=1
    error("sixgr:phy:ia:c0:partial:FalseAlarmSummary", ...
        "Expected exactly one persisted false-alarm summary row.");
end
thresholds=struct("PSSStageThreshold",double(S.PSSStageThreshold), ...
    "GlobalDeclarationThreshold",double(S.GlobalDeclarationThreshold));
calibration=struct("Threshold",double(S.GlobalDeclarationThreshold), ...
    "Thresholds",thresholds, ...
    "PSSStageThreshold",double(S.PSSStageThreshold), ...
    "Metrics",double(C.FinalDeclarationStatistic), ...
    "PSSMetrics",double(C.PSSStatistic), ...
    "SSSMetrics",double(C.SSSNormalizedStatistic), ...
    "JointMetricsBeforePSSStage",double(C.JointStatisticBeforePSSStage), ...
    "Seeds",double(C.Seed),"SeedFirst",double(S.CalibrationSeedFirst), ...
    "SeedLast",double(S.CalibrationSeedLast), ...
    "TrialCount",double(S.CalibrationTrials), ...
    "ReceiverExceptionCount",double(S.CalibrationReceiverExceptions), ...
    "ExceedanceCount",nnz(C.Exceeded), ...
    "ThresholdOrderStatisticIndex",double(S.ThresholdOrderStatisticIndex));
validation=struct("Threshold",double(S.GlobalDeclarationThreshold), ...
    "Thresholds",thresholds, ...
    "PSSStageThreshold",double(S.PSSStageThreshold), ...
    "Metrics",double(V.JointDeclarationStatistic), ...
    "Declared",logical(V.FalseAlarm),"Seeds",double(V.Seed), ...
    "SeedFirst",double(S.ValidationSeedFirst), ...
    "SeedLast",double(S.ValidationSeedLast), ...
    "TrialCount",double(S.ValidationTrials), ...
    "ReceiverExceptionCount",double(S.ValidationReceiverExceptions), ...
    "FalseAlarms",double(S.FalseAlarms), ...
    "EmpiricalPFA",double(S.EmpiricalPFA), ...
    "CILow",double(S.CILow),"CIHigh",double(S.CIHigh), ...
    "RelativeCIHalfWidth",double(S.RelativeCIHalfWidth), ...
    "TargetPFA",double(S.TargetPFA), ...
    "TargetInsideCI",logical(S.TargetInsideCI), ...
    "CIPrecisionPassed",logical(S.CIPrecisionPassed), ...
    "Passed",logical(S.Passed), ...
    "IndependentFromCalibration",logical(S.IndependentSeedRanges));
if calibration.TrialCount~=height(C)||validation.TrialCount~=height(V)|| ...
        calibration.TrialCount~=double(cfg.false_alarm.calibration_trials)|| ...
        validation.TrialCount~=double(cfg.false_alarm.validation_trials)
    error("sixgr:phy:ia:c0:partial:FalseAlarmRowCount", ...
        "Persisted false-alarm row counts do not match the resolved configuration.");
end
end

function hash=localFileHash(path)
hash=sixgr.phy.waveform.WaveformArtifactExporter.fileSHA256(path);
end

function localReport(folder,manifest,gates)
failed=gates.Check(~gates.Pass);
lines=["# Partial C0 engineering result";""; ...
    "- Completion: **PARTIAL — stopped by user**"; ...
    "- Claim: `PARTIAL_ENGINEERING_NOT_TDOC`"; ...
    "- Actual waveform trials: "+manifest.RawTrialCount; ...
    "- Completed SNR points (dB): `"+mat2str(manifest.CompletedSNRDB)+"`"; ...
    "- Partial SNR points (dB): `"+mat2str(manifest.PartialSNRDB)+"`"; ...
    "- Missing planned SNR points (dB): `"+mat2str(manifest.MissingPlannedSNRDB)+"`"; ...
    "- False alarm: "+manifest.ValidationPFA+" (95% CI "+ ...
        manifest.ValidationPFACILow+" to "+manifest.ValidationPFACIHigh+")"; ...
    "- Figure artifact integrity: "+manifest.ArtifactIntegrityPassed; ...
    "- Scientific completion: **false**";""; ...
    "## Failed or incomplete gates";""];
if isempty(failed), lines(end+1)="None"; else, lines=[lines;"- "+failed]; end
sixgr.util.writeTextFile(fullfile(folder,"run_summary.md"), ...
    strjoin(lines,newline),"MimeType","text/markdown");
end
