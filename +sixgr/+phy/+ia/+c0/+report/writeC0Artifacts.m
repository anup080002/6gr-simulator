function artifacts = writeC0Artifacts(runFolder,cfg,raw,points,crossings,calibration,validation)
%WRITEC0ARTIFACTS Publish the canonical C0 CSV contract from raw truth.
runMode=upper(string(cfg.run.mode));
summary=table(string(cfg.meta.scenario_id),runMode,height(raw),height(points), ...
    calibration.TrialCount,validation.TrialCount,validation.FalseAlarms, ...
    calibration.SeedFirst,calibration.SeedLast,validation.SeedFirst, ...
    validation.SeedLast,validation.IndependentFromCalibration, ...
    calibration.ReceiverExceptionCount,validation.ReceiverExceptionCount, ...
    validation.EmpiricalPFA,validation.CILow,validation.CIHigh, ...
    validation.RelativeCIHalfWidth,nnz(crossings.Bracketed), ...
    'VariableNames',{'ScenarioID','RunMode','RawTrials','SNRPoints', ...
    'CalibrationNoiseWindows','ValidationNoiseWindows','ValidationFalseAlarms', ...
    'CalibrationSeedFirst','CalibrationSeedLast','ValidationSeedFirst', ...
    'ValidationSeedLast','IndependentSeedRanges', ...
    'CalibrationReceiverExceptions','ValidationReceiverExceptions', ...
    'ValidationPFA','ValidationPFACILow','ValidationPFACIHigh', ...
    'ValidationPFARelativeCIHalfWidth','BracketedGammaRows'});
falseAlarm=table(runMode,calibration.TrialCount,validation.TrialCount, ...
    calibration.SeedFirst,calibration.SeedLast,validation.SeedFirst, ...
    validation.SeedLast,validation.IndependentFromCalibration, ...
    calibration.ReceiverExceptionCount,validation.ReceiverExceptionCount, ...
    calibration.ThresholdOrderStatisticIndex,calibration.PSSStageThreshold, ...
    calibration.Threshold,validation.FalseAlarms,validation.EmpiricalPFA, ...
    validation.CILow,validation.CIHigh,validation.RelativeCIHalfWidth, ...
    validation.TargetPFA,validation.TargetInsideCI, ...
    validation.CIPrecisionPassed,validation.Passed, ...
    'VariableNames',{'RunMode','CalibrationNoiseWindows', ...
    'ValidationNoiseWindows','CalibrationSeedFirst','CalibrationSeedLast', ...
    'ValidationSeedFirst','ValidationSeedLast','IndependentSeedRanges', ...
    'CalibrationReceiverExceptions','ValidationReceiverExceptions', ...
    'ThresholdOrderStatisticIndex', ...
    'PSSStageThreshold','GlobalDeclarationThreshold','ValidationFalseAlarms', ...
    'ValidationPFA','CILow','CIHigh','RelativeCIHalfWidth','TargetPFA', ...
    'TargetInsideCI','CIPrecisionPassed','Passed'});
timing=raw(:,intersect(["RunMode" "SNRDB" "Trial" "TrueOccurrence" ...
    "DetectedOccurrence" "AppliedTimingSamples" "EstimatedTimingSamples" ...
    "TimingErrorSamples" "FineTimingErrorSamples" "FineTimingErrorMicroseconds" ...
    "TimingSuccessToleranceSamples" "CorrectOccurrence" ...
    "TimingWithinTolerance" "TimingValidPopulation" "FailureStage"], ...
    string(raw.Properties.VariableNames),"stable"));
cfo=raw(:,intersect(["RunMode" "SNRDB" "Trial" "UEOscillatorHz" ...
    "TRPOscillatorHz" "AppliedCFOHz" "CoarseCFOEstimateHz" ...
    "FineCFOEstimateHz" "EstimatedCFOHz" "CFOErrorHz" ...
    "ResidualCFOBeforeSSS_Hz" "ResidualCFOBeforePBCH_Hz" ...
    "CFOValidPopulation" "ConditionalResidualCFOHz" "FailureStage"], ...
    string(raw.Properties.VariableNames),"stable"));
channel=raw(:,intersect(["RunMode" "SNRDB" "Trial" ...
    "CorrectPCIDeclared" "PBCHAttempted" "TrueDMRSHypothesis" ...
    "EstimatedDMRSHypothesis" "ChannelEstimateMSEAvailable" ...
    "ChannelEstimateNMSE" "ChannelEstimateNMSEDB" ...
    "ChannelEstimateSquaredError" "ChannelEstimateTruthEnergy" ...
    "PBCHReceiverSINRDB" "PBCHPostEqSINRDB" "FailureStage"], ...
    string(raw.Properties.VariableNames),"stable"));
complexityRaw=raw(:,intersect(["RunMode" "SNRDB" "Trial" "RasterPoints" ...
    "InputTimeSamplesSearched" "TimingLagsEvaluated" ...
    "CoarseCFOHypotheses" "FineCFOHypotheses" "PSSSequences" ...
    "PSSCorrelationVectors" "PSSComplexMultiplications" ...
    "PSSComplexAdditions" "FFTCount" "SSSSequenceHypotheses" ...
    "SSSComplexMultiplications" "SSSComplexAdditions" ...
    "DMRSHypothesesTested" "ChannelEstimationOperations" ...
    "PBCHDemaps" "PolarDecodes" "PeakSoftBufferBytes" ...
    "BufferTimeProductByteSamples" "RFActiveSamples" ...
    "RFActiveTimeSeconds"],string(raw.Properties.VariableNames),"stable"));
complexity=localComplexitySummary(complexityRaw);
failureBreakdown=localFailureBreakdown(raw);
counterAudit=localCounterAudit(raw);

debug=localDebugRows(raw,double(cfg.run.save_debug_trials));
artifacts=struct("Summary",summary,"Points",points,"Gamma",crossings, ...
    "FalseAlarm",falseAlarm,"Timing",timing,"CFO",cfo, ...
    "ChannelEstimation",channel,"Complexity",complexity, ...
    "FailureBreakdown",failureBreakdown,"CounterAudit",counterAudit, ...
    "Debug",debug);
names=["C0_summary.csv" "C0_points.csv" "C0_gamma.csv" ...
    "C0_false_alarm.csv" "C0_timing.csv" "C0_cfo.csv" ...
    "C0_channel_estimation.csv" "C0_complexity.csv" ...
    "C0_failure_breakdown.csv" "C0_counter_audit.csv" "C0_event_debug.csv"];
tables={summary,points,crossings,falseAlarm,timing,cfo,channel,complexity, ...
    failureBreakdown,counterAudit,debug};
for k=1:numel(names)
    writetable(tables{k},fullfile(runFolder,names(k)));
end

function result=localCounterAudit(raw)
snrs=unique(raw.SNRDB,"sorted"); rows=cell(numel(snrs),1);
for k=1:numel(snrs)
    T=raw(raw.SNRDB==snrs(k),:); n=height(T);
    pssSuccess=T.PSSDetected;
    sssEligible=T.ConditionalSSSEligible;
    sssSuccess=T.ConditionalSSSSuccess;
    joint=T.CellDeclared&T.PSSIdentityCorrect&T.SSSCorrect;
    conditionalPBCH=T.PBCHConditionalAttempted;
    rows{k}=table(snrs(k),n,nnz(~pssSuccess),nnz(pssSuccess), ...
        nnz(sssEligible&~sssSuccess),nnz(sssEligible), ...
        nnz(~joint),nnz(joint),nnz(T.WrongPCIDeclared), ...
        nnz(conditionalPBCH),nnz(conditionalPBCH&~T.PBCHConditionalOk), ...
        nnz(T.CompleteSSBSuccess),nnz(~T.CompleteSSBSuccess), ...
        'VariableNames',{'snrDb','totalTrials','pssMisses','pssSuccesses', ...
        'sssErrorsConditional','sssConditionalDenominator','jointSSErrors', ...
        'jointSSSuccesses','wrongPCIDeclarations','pbchAttempts', ...
        'pbchErrorsConditional','completeSSBSuccesses','completeSSBFailures'});
end
result=vertcat(rows{:});
end
end

function result=localComplexitySummary(raw)
idNames=["RunMode" "SNRDB" "Trial"];
metrics=setdiff(string(raw.Properties.VariableNames),idNames,"stable");
snrs=unique(raw.SNRDB,"sorted"); rows=cell(numel(snrs)*numel(metrics),1); n=0;
for i=1:numel(snrs)
    T=raw(raw.SNRDB==snrs(i),:);
    for j=1:numel(metrics)
        n=n+1; values=double(T.(metrics(j))); values=values(isfinite(values));
        rows{n}=table(upper(string(T.RunMode(1))),snrs(i),metrics(j),numel(values), ...
            mean(values,"omitnan"),prctile(values,50),prctile(values,95), ...
            'VariableNames',{'RunMode','SNRDB','Metric','Samples','Mean','P50','P95'});
    end
end
result=vertcat(rows{1:n});
end

function result=localFailureBreakdown(raw)
snrs=unique(raw.SNRDB,"sorted"); categories=unique(raw.FailureStage,"stable");
rows=cell(numel(snrs)*numel(categories),1); n=0;
for i=1:numel(snrs)
    T=raw(raw.SNRDB==snrs(i),:);
    for j=1:numel(categories)
        n=n+1; count=nnz(T.FailureStage==categories(j));
        rows{n}=table(snrs(i),categories(j),count,count/height(T),height(T), ...
            'VariableNames',{'SNRDB','FailureStage','Trials','Probability','TotalTrials'});
    end
end
result=vertcat(rows{1:n});
end

function debug=localDebugRows(raw,perCategory)
fail=raw(raw.FailureStage~="SUCCESS",intersect(["Trial" "SNRDB" ...
    "ChannelSeed" "CFOSeed" "NoiseSeed" "TimingSeed" ...
    "AppliedTimingSamples" "EstimatedTimingSamples" "TruePSSNID2" ...
    "EstimatedPSSNID2" "TruePCI" "EstimatedPCI" "AppliedCFOHz" ...
    "CoarseCFOEstimateHz" "FineCFOEstimateHz" "CFOErrorHz" ...
    "PSSMetric" "PSSStageThreshold" "SSSNormalizedMetric" ...
    "SSSNormalizedMetricMargin" "JointDeclarationStatistic" ...
    "FalseAlarmThreshold" "TrueDMRSHypothesis" ...
    "EstimatedDMRSHypothesis" "ChannelEstimateNMSE" "PBCHOk" ...
    "FailureStage" "FailureReason"],string(raw.Properties.VariableNames),"stable"));
if isempty(fail)
    debug=fail;
    return;
end
keep=false(height(fail),1);
categories=unique(fail.FailureStage,"stable");
for k=1:numel(categories)
    idx=find(fail.FailureStage==categories(k),perCategory,"first");
    keep(idx)=true;
end
debug=fail(keep,:);
end
