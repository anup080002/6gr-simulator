function result = runBlindPSSSearch(rxWaveform,bundle,cfg)
%RUNBLINDPSSSEARCH Execute configured production timing/CFO/NID2 search.
phyCfg = sixgr.phy.ia.c0.config.toPHYConfig(cfg);
timing = localTiming(cfg);
[corrected,cfoHz,nid2,info] = sixgr.phy.sync.freqOffsetCorrect( ...
    rxWaveform,char(string(cfg.waveform.block_pattern)),bundle.SampleRateHz, ...
    "SearchBW_Hz",max(abs(double(cfg.search.cfo_hypotheses_hz))), ...
    "CFOHypothesesHz",double(cfg.search.cfo_hypotheses_hz), ...
    "NID2Candidates",double(cfg.search.nid2_hypotheses), ...
    "TimingSearchGuardSamples",double(cfg.search.timing_uncertainty_samples), ...
    "SSBTiming",timing);
result = struct( ...
    "CorrectedWaveform",corrected, ...
    "CFOEstimateHz",double(cfoHz), ...
    "NID2",double(nid2), ...
    "TimingEstimateSamples",double(info.SelectedTimingOffsetSamples), ...
    "Metric",double(info.Metric), ...
    "Info",info, ...
    "HypothesisCount",double(numel(info.Candidates_Hz)* ...
        numel(info.Candidates_NID2)*size(info.CandidateSearchWindows,1)), ...
    "PHYConfig",phyCfg);
end

function timing = localTiming(cfg)
timing = sixgr.phy.frame.SSBTimingResolver.resolve( ...
    "Case",string(cfg.waveform.block_pattern), ...
    "CarrierFrequencyHz",double(cfg.carrier.frequency_hz), ...
    "FrequencyRange","FR1", ...
    "SSBSubcarrierSpacingKHz",double(cfg.carrier.scs_khz), ...
    "CarrierSubcarrierSpacingKHz",double(cfg.carrier.scs_khz), ...
    "Lmax",double(cfg.waveform.lmax), ...
    "PeriodicityMs",20, ...
    "SSBIndex",double(cfg.waveform.ssb_index), ...
    "NStartGrid",0,"NSizeGrid",double(cfg.carrier.n_size_grid), ...
    "NStartBWP",0,"NSizeBWP",double(cfg.carrier.n_size_grid), ...
    "NCRBSSB",0,"KSSB",double(cfg.waveform.k_ssb), ...
    "ActiveBitmap","10000000");
end
