function validation = validateGlobalFalseAlarm(bundle,cfg,calibration,varargin)
%VALIDATEGLOBALFALSEALARM Validate complete declaration on disjoint seeds.
p=inputParser;
p.addParameter("CheckpointPath","",@(x)ischar(x)||isstring(x));
p.addParameter("ProgressCSVPath","",@(x)ischar(x)||isstring(x));
p.parse(varargin{:});
if isstruct(calibration)&&isfield(calibration,"Thresholds")
    thresholds=calibration.Thresholds;
    calibrationRange=[double(calibration.SeedFirst) double(calibration.SeedLast)];
elseif isnumeric(calibration)&&isscalar(calibration)
    thresholds=struct("PSSStageThreshold",-Inf, ...
        "GlobalDeclarationThreshold",double(calibration));
    calibrationRange=double(cfg.run.seed_set_calibration)+ ...
        [1 double(cfg.false_alarm.calibration_trials)];
else
    thresholds=calibration;
    calibrationRange=double(cfg.run.seed_set_calibration)+ ...
        [1 double(cfg.false_alarm.calibration_trials)];
end
checkpointPath=string(p.Results.CheckpointPath);
progressPath=string(p.Results.ProgressCSVPath);
nTrials=double(cfg.false_alarm.validation_trials);
nRx=double(cfg.mimo.num_rx_antennas);
guard=double(cfg.search.timing_uncertainty_samples);
nSamples=size(bundle.Waveform,1)+2*guard;
seed0=double(cfg.run.seed_set_validation);
seeds=seed0+(1:nTrials)';
validationRange=[seeds(1) seeds(end)];
independent=max(calibrationRange(1),validationRange(1))> ...
    min(calibrationRange(2),validationRange(2));
if ~independent
    error("sixgr:phy:ia:c0:falseAlarm:SeedRangeOverlap", ...
        "Calibration seeds [%.0f,%.0f] overlap validation seeds [%.0f,%.0f].", ...
        calibrationRange(1),calibrationRange(2),validationRange(1),validationRange(2));
end
searchHash=string(sixgr.util.sha256Hex(uint8( ...
    unicode2native(jsonencode(cfg.search),"UTF-8"))));
[metrics,declared,completed]=localRestore( ...
    checkpointPath,nTrials,seed0,searchHash,thresholds);
cfgPHY=sixgr.phy.ia.c0.config.toPHYConfig(cfg);
cfgPHY.phy.sampleRate_Hz=double(bundle.SampleRateHz);
progressEvery=double(cfg.false_alarm.progress_interval);
checkpointEvery=double(cfg.false_alarm.checkpoint_interval);
started=tic;
old=rng;
cleanup=onCleanup(@()rng(old)); %#ok<NASGU>
for trial=completed+1:nTrials
    rng(seeds(trial),"twister");
    noise=(randn(nSamples,nRx)+1j*randn(nSamples,nRx))/sqrt(2);
    try
        [~,sync]=sixgr.phy.dl.SSB_Rx(noise,cfgPHY, ...
            "SampleRate_Hz",bundle.SampleRateHz);
        d=sixgr.phy.ia.c0.receiver.declarationMetrics(sync,cfg,thresholds);
    catch ME
        localCheckpoint(checkpointPath,metrics,declared,trial-1,nTrials, ...
            seed0,searchHash,thresholds);
        localProgress(progressPath,"VALIDATION","FAILED",trial-1,nTrials, ...
            seed0,seeds(max(trial-1,1)),toc(started),1,nnz(declared),ME.identifier);
        failure=MException("sixgr:phy:ia:c0:falseAlarm:ValidationReceiverFailure", ...
            "Complete blind receiver failed at validation window %d (seed %.0f): %s | %s", ...
            trial,seeds(trial),ME.identifier,ME.message);
        failure=addCause(failure,ME);
        throw(failure);
    end
    metrics(trial)=d.JointDeclarationStatistic;
    declared(trial)=d.CellDeclared;
    if mod(trial,progressEvery)==0 || trial==nTrials
        alarms=nnz(declared(1:trial));
        localProgress(progressPath,"VALIDATION","RUNNING",trial,nTrials, ...
            seed0,seeds(trial),toc(started),0,alarms,"");
        fprintf('[C0][%s][FA_VALIDATION] completed=%d/%d (%.3f%%) seed=%.0f false_alarms=%d exceptions=0\n', ...
            upper(string(cfg.run.mode)),trial,nTrials,100*trial/nTrials,seeds(trial),alarms);
    end
    if mod(trial,checkpointEvery)==0 || trial==nTrials
        localCheckpoint(checkpointPath,metrics,declared,trial,nTrials, ...
            seed0,searchHash,thresholds);
    end
end
alarms=nnz(declared);
confidence=double(cfg.statistics.confidence_level);
[~,~,low,high]=sixgr.stats.wilsonBinomialCI(alarms,nTrials,confidence);
target=double(cfg.false_alarm.target_probability);
relativeHalfWidth=(high-low)/(2*target);
localProgress(progressPath,"VALIDATION","COMPLETE",nTrials,nTrials, ...
    seed0,seeds(end),toc(started),0,alarms,"");
validation=struct("Threshold",double(thresholds.GlobalDeclarationThreshold), ...
    "Thresholds",thresholds, ...
    "PSSStageThreshold",double(thresholds.PSSStageThreshold), ...
    "Metrics",metrics,"Declared",declared,"Seeds",seeds, ...
    "SeedFirst",seeds(1),"SeedLast",seeds(end),"TrialCount",nTrials, ...
    "ReceiverExceptionCount",0,"FalseAlarms",alarms, ...
    "EmpiricalPFA",alarms/nTrials,"CILow",low,"CIHigh",high, ...
    "RelativeCIHalfWidth",relativeHalfWidth,"TargetPFA",target, ...
    "TargetInsideCI",low<=target&&high>=target, ...
    "CIPrecisionPassed",relativeHalfWidth<=double( ...
        cfg.false_alarm.relative_ci_half_width_limit), ...
    "Passed",low<=target&&high>=target&& ...
        relativeHalfWidth<=double(cfg.false_alarm.relative_ci_half_width_limit), ...
    "SeedBase",seed0,"CalibrationSeedFirst",calibrationRange(1), ...
    "CalibrationSeedLast",calibrationRange(2), ...
    "DeclarationPath","blind_pss_timing_cfo_nid2_then_all_pci_sss_confirmation", ...
    "IndependentFromCalibration",independent);
end

function [metrics,declared,completed]=localRestore(path,nTrials,seedBase,searchHash,thresholds)
metrics=-inf(nTrials,1); declared=false(nTrials,1); completed=0;
if strlength(path)==0 || ~isfile(path), return; end
saved=load(path,"checkpoint");
thresholdHash=localThresholdHash(thresholds);
if ~isfield(saved,"checkpoint") || ...
        saved.checkpoint.TotalTrials~=nTrials || ...
        saved.checkpoint.SeedBase~=seedBase || ...
        string(saved.checkpoint.SearchHash)~=searchHash || ...
        string(saved.checkpoint.ThresholdHash)~=thresholdHash
    error("sixgr:phy:ia:c0:falseAlarm:CheckpointMismatch", ...
        "Validation checkpoint does not match the resolved trials, seeds, search configuration, or thresholds.");
end
checkpoint=saved.checkpoint; completed=double(checkpoint.CompletedTrials);
metrics=checkpoint.Metrics; declared=checkpoint.Declared;
end

function localCheckpoint(path,metrics,declared,completed,total,seedBase,searchHash,thresholds)
if strlength(path)==0, return; end
checkpoint=struct("Stage","VALIDATION","CompletedTrials",completed, ...
    "TotalTrials",total,"SeedBase",seedBase,"SearchHash",searchHash, ...
    "ThresholdHash",localThresholdHash(thresholds), ...
    "Metrics",metrics,"Declared",declared); %#ok<NASGU>
save(path,"checkpoint","-v7.3");
end

function hash=localThresholdHash(thresholds)
hash=string(sixgr.util.sha256Hex(uint8(unicode2native( ...
    jsonencode(thresholds),"UTF-8"))));
end

function localProgress(path,stage,status,completed,total,seedBase,lastSeed,elapsed,exceptions,alarms,errorID)
if strlength(path)==0, return; end
progress=table(string(stage),string(status),completed,total,100*completed/total, ...
    seedBase+1,lastSeed,elapsed,exceptions,alarms,string(errorID), ...
    string(datetime("now","TimeZone","UTC","Format","yyyy-MM-dd'T'HH:mm:ss.SSSXXX")), ...
    'VariableNames',{'Stage','Status','CompletedTrials','TotalTrials','Percent', ...
    'FirstSeed','LastCompletedSeed','InvocationElapsedSeconds', ...
    'ReceiverExceptions','FalseAlarmsSoFar','ErrorIdentifier','UpdatedUTC'});
writetable(progress,path);
end
