function validation = validateGlobalFalseAlarm(bundle,cfg,threshold)
%VALIDATEGLOBALFALSEALARM Validate calibrated PFA on independent noise.
nTrials = double(cfg.false_alarm.validation_trials);
nRx = double(cfg.mimo.num_rx_antennas);
guard = double(cfg.search.timing_uncertainty_samples);
nSamples = size(bundle.Waveform,1)+2*guard;
metrics = zeros(nTrials,1);
seed0 = double(cfg.run.seed_set_validation);
for trial = 1:nTrials
    old = rng;
    cleanup = onCleanup(@()rng(old)); %#ok<NASGU>
    rng(seed0+trial,"twister");
    noise = (randn(nSamples,nRx)+1j*randn(nSamples,nRx))/sqrt(2);
    metrics(trial) = sixgr.phy.ia.c0.search.runBlindPSSSearch( ...
        noise,bundle,cfg).Metric;
end
alarms = nnz(metrics>=threshold);
confidence = double(cfg.statistics.confidence_level);
[~,~,low,high] = sixgr.stats.wilsonBinomialCI(alarms,nTrials,confidence);
target = double(cfg.false_alarm.target_probability);
validation = struct( ...
    "Threshold",double(threshold), ...
    "Metrics",metrics, ...
    "TrialCount",nTrials, ...
    "FalseAlarms",alarms, ...
    "EmpiricalPFA",alarms/nTrials, ...
    "CILow",low,"CIHigh",high, ...
    "TargetPFA",target, ...
    "Passed",low<=target && high>=target, ...
    "SeedBase",seed0, ...
    "IndependentFromCalibration",double(cfg.run.seed_set_calibration)~=seed0);
end
