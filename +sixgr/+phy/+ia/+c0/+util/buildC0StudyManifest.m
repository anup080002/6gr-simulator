function manifest = buildC0StudyManifest(cfg,configMeta,runFolder,trialCount,figureCount)
%BUILDMANIFEST Build exact production C0 runtime provenance.
[~,commit]=system("git rev-parse HEAD");
[dirtyStatus,dirtyText]=system("git status --porcelain");
v=ver("5g");
manifest=struct( ...
    "SchemaVersion","sixgr.phy.ia.c0.run.v1", ...
    "ScenarioID",string(cfg.meta.scenario_id), ...
    "RunMode",upper(string(cfg.run.mode)), ...
    "ClaimClass",localClaim(cfg), ...
    "RunFolder",string(runFolder), ...
    "ConfigHash",string(configMeta.ConfigHash), ...
    "ConfigSources",configMeta.SourceFiles, ...
    "GitCommit",string(strtrim(commit)), ...
    "GitWorktreeDirty",dirtyStatus~=0 || strlength(strtrim(string(dirtyText)))>0, ...
    "MATLABRelease",string(version("-release")), ...
    "MATLABVersion",string(version), ...
    "FiveGToolboxVersion",string(v.Version), ...
    "SeedPolicy","disjoint_snr_domain_trial_blocks_v1", ...
    "MainSeedBase",double(cfg.run.seed_set_main), ...
    "CalibrationSeedFirst",double(cfg.run.seed_set_calibration)+1, ...
    "CalibrationSeedLast",double(cfg.run.seed_set_calibration)+ ...
        double(cfg.false_alarm.calibration_trials), ...
    "ValidationSeedFirst",double(cfg.run.seed_set_validation)+1, ...
    "ValidationSeedLast",double(cfg.run.seed_set_validation)+ ...
        double(cfg.false_alarm.validation_trials), ...
    "TrialCount",double(trialCount), ...
    "FigureCount",double(figureCount), ...
    "GeneratedUTC",string(datetime("now","TimeZone","UTC","Format","yyyy-MM-dd'T'HH:mm:ss'Z'")));
end
function value=localClaim(cfg)
if any(strcmpi(string(cfg.run.mode),["tdoc" "exhaustive"]))
    value="SIMULATED_TDOC_GRADE_PENDING_GATES";
elseif strcmpi(string(cfg.run.mode),"quick_sanity")
    value="QUICK_SANITY";
else
    value="SMOKE_NO_NUMERICAL_CLAIM";
end
end
