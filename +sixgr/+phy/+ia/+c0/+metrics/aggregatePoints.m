function points = aggregatePoints(raw,cfg)
%AGGREGATEPOINTS Reduce actual C0 trial rows into per-SNR statistics.
arguments
    raw table
    cfg (1,1) struct
end
if isempty(raw)
    error("sixgr:phy:ia:c0:metrics:EmptyRawTrials", ...
        "C0 point aggregation requires at least one actual waveform trial.");
end
snrs=unique(raw.SNRDB,"sorted");
confidence=double(cfg.statistics.confidence_level);
rows=cell(numel(snrs),1);
for k=1:numel(snrs)
    T=raw(raw.SNRDB==snrs(k),:); n=height(T);
    pssErr=nnz(~T.PSSDetected);
    pssIdentityErr=nnz(T.PSSDetected&~T.PSSIdentityCorrect);
    jointErr=nnz(~(T.CellDeclared&T.PSSIdentityCorrect&T.SSSCorrect));
    cond=T.ConditionalSSSEligible;
    condN=nnz(cond);
    condSSSuccess=T.ConditionalSSSSuccess;
    condErr=nnz(cond&~condSSSuccess);
    pbchN=nnz(T.PBCHComponentAttempted);
    pbchErr=nnz(T.PBCHComponentAttempted&~T.PBCHComponentOk);
    pbchConditionalN=nnz(T.PBCHConditionalAttempted);
    pbchConditionalErr=nnz(T.PBCHConditionalAttempted&~T.PBCHConditionalOk);
    wrong=nnz(T.WrongPCIDeclared); declared=nnz(T.CellDeclared);
    noDeclaration=nnz(T.NoCellDeclared);
    correctDeclaration=nnz(T.CorrectPCIDeclared);
    completeErr=nnz(~T.CompleteSSBSuccess);
    oracleErr=nnz(~T.OracleCompleteSSBSuccess);
    a=sixgr.phy.ia.c0.metrics.binomialCI(pssErr,n,confidence);
    b=sixgr.phy.ia.c0.metrics.binomialCI(jointErr,n,confidence);
    c=sixgr.phy.ia.c0.metrics.binomialCI(condErr,condN,confidence);
    d=sixgr.phy.ia.c0.metrics.binomialCI(pbchErr,pbchN,confidence);
    dConditional=sixgr.phy.ia.c0.metrics.binomialCI( ...
        pbchConditionalErr,pbchConditionalN,confidence);
    e=sixgr.phy.ia.c0.metrics.binomialCI(wrong,n,confidence);
    eConditional=sixgr.phy.ia.c0.metrics.binomialCI(wrong,declared,confidence);
    f=sixgr.phy.ia.c0.metrics.binomialCI(completeErr,n,confidence);
    g=sixgr.phy.ia.c0.metrics.binomialCI(oracleErr,n,confidence);
    rows{k}=struct("SNRDB",snrs(k),"Trials",n, ...
        "PSSMissErrors",pssErr,"PSSMissProbability",a.Estimate,"PSSMissCILow",a.CILow,"PSSMissCIHigh",a.CIHigh, ...
        "PSSIdentityErrors",pssIdentityErr, ...
        "JointSSErrors",jointErr,"JointSSMDR",b.Estimate,"JointSSCILow",b.CILow,"JointSSCIHigh",b.CIHigh, ...
        "ConditionalSSSTrials",condN,"ConditionalSSSErrors",condErr,"ConditionalSSSError",c.Estimate, ...
        "ConditionalSSSCILow",c.CILow,"ConditionalSSSCIHigh",c.CIHigh, ...
        "PBCHTrials",pbchN,"PBCHErrors",pbchErr,"PBCHBLER",d.Estimate,"PBCHCILow",d.CILow,"PBCHCIHigh",d.CIHigh, ...
        "PBCHComponentTrials",pbchN,"PBCHComponentErrors",pbchErr, ...
        "PBCHComponentBLER",d.Estimate,"PBCHComponentCILow",d.CILow, ...
        "PBCHComponentCIHigh",d.CIHigh, ...
        "PBCHConditionalTrials",pbchConditionalN, ...
        "PBCHConditionalErrors",pbchConditionalErr, ...
        "PBCHConditionalBLER",dConditional.Estimate, ...
        "PBCHConditionalCILow",dConditional.CILow, ...
        "PBCHConditionalCIHigh",dConditional.CIHigh, ...
        "NoCellDeclared",noDeclaration,"CorrectPCIDeclared",correctDeclaration, ...
        "WrongPCIDeclared",wrong,"TotalCellDeclarations",declared, ...
        "WrongPCIErrors",wrong,"WrongPCIProbability",e.Estimate, ...
        "WrongPCICILow",e.CILow,"WrongPCICIHigh",e.CIHigh, ...
        "WrongPCIGivenDeclaration",eConditional.Estimate, ...
        "WrongPCIGivenDeclarationCILow",eConditional.CILow, ...
        "WrongPCIGivenDeclarationCIHigh",eConditional.CIHigh, ...
        "CompleteSSBErrors",completeErr,"CompleteSSBSuccessProbability",1-f.Estimate, ...
        "CompleteSSBSuccessCILow",1-f.CIHigh,"CompleteSSBSuccessCIHigh",1-f.CILow, ...
        "OracleCompleteSSBSuccessProbability",mean(T.OracleCompleteSSBSuccess), ...
        "OracleCompleteSSBSuccessCILow",1-g.CIHigh, ...
        "OracleCompleteSSBSuccessCIHigh",1-g.CILow, ...
        "JointSSStoppingQualified",jointErr>=double(cfg.run.min_errors_per_snr)||n>=double(cfg.run.max_trials_per_snr), ...
        "PBCHComponentStoppingQualified",pbchErr>=double(cfg.run.min_errors_per_snr)||n>=double(cfg.run.max_trials_per_snr), ...
        "CompleteSSBStoppingQualified",completeErr>=double(cfg.run.min_errors_per_snr)||n>=double(cfg.run.max_trials_per_snr), ...
        "MeanMeasuredInputSNRDB",mean(T.MeasuredInputSNRDB,"omitnan"), ...
        "TimingValidTrials",nnz(T.TimingValidPopulation), ...
        "TimingRMSESamples",sqrt(mean(T.FineTimingErrorSamples.^2,"omitnan")), ...
        "GrossTimingOccurrenceErrors",nnz(~T.CorrectOccurrence), ...
        "GrossTimingOccurrenceProbability",mean(~T.CorrectOccurrence), ...
        "CFOValidTrials",nnz(T.CFOValidPopulation), ...
        "CFORMSEHz",sqrt(mean(T.ConditionalResidualCFOHz.^2,"omitnan")), ...
        "ChannelEstimateNMSE",mean(T.ChannelEstimateNMSE,"omitnan"), ...
        "ChannelEstimateNMSEDB",10*log10(max(mean(T.ChannelEstimateNMSE,"omitnan"),realmin)), ...
        "MeanSearchHypotheses",mean(T.SearchHypotheses,"omitnan"), ...
        "MeanDMRSHypotheses",mean(T.DMRSHypothesesTested,"omitnan"), ...
        "MeanPolarDecodes",mean(T.PolarDecodes,"omitnan"), ...
        "Status","SIMULATED","EvidenceClass","actual_nr_ssb_waveform_receiver_truth");
end
points=struct2table(vertcat(rows{:}),"AsArray",true);
end
