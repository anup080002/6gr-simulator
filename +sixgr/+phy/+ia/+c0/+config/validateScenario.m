function validateScenario(cfg)
%VALIDATESCENARIO Fail-closed validation for production C0 configurations.
if ~(isstruct(cfg) && isscalar(cfg))
    error("sixgr:phy:ia:c0:config:BadTopLevel", ...
        "Resolved C0 IA config must be a scalar struct.");
end
s = sixgr.phy.ia.c0.config.schema();
required = string(s.required_paths);
for k = 1:numel(required)
    value = sixgr.util.structGet(cfg,required(k),[]);
    if isempty(value)
        error("sixgr:phy:ia:c0:config:MissingField", ...
            "Required IA configuration field '%s' is missing.",required(k));
    end
end
localEnum(cfg,"run.mode",string(s.allowed_run_modes));
localEnum(cfg,"meta.research_class",string(s.allowed_research_classes));
localEnum(cfg,"channel.model",string(s.allowed_channels));
localEnum(cfg,"waveform.normalization",string(s.allowed_normalizations));
localEnum(cfg,"waveform.candidate",string(s.allowed_candidates));
localEnum(cfg,"search.declaration_statistic",string(s.allowed_declaration_statistics));
localEnum(cfg,"search.fine_cfo.method",string(s.allowed_fine_cfo_methods));
localEnum(cfg,"receiver.pbch_component_residual_cfo_model", ...
    string(s.allowed_pbch_component_residual_cfo_models));
if string(cfg.meta.scenario_id) ~= "JIO_RAN1_126_AI_10_5_1_1_C0"
    error("sixgr:phy:ia:c0:config:PhaseGate", ...
        "Phase 1 permits only scenario JIO_RAN1_126_AI_10_5_1_1_C0.");
end
localScalar(cfg.carrier.frequency_hz,0,Inf,"carrier.frequency_hz");
localScalar(cfg.carrier.scs_khz,0,Inf,"carrier.scs_khz");
localInteger(cfg.carrier.n_size_grid,1,275,"carrier.n_size_grid");
if double(cfg.carrier.frequency_hz) ~= 7e9 || ...
        double(cfg.carrier.scs_khz) ~= 30 || ...
        double(cfg.carrier.n_size_grid) ~= 20
    error("sixgr:phy:ia:c0:config:C0CarrierContract", ...
        "C0 requires carrier.frequency_hz=7e9, carrier.scs_khz=30, and carrier.n_size_grid=20.");
end
localInteger(cfg.waveform.n_cell_id,0,1007,"waveform.n_cell_id");
localInteger(cfg.waveform.ssb_index,0,7,"waveform.ssb_index");
localInteger(cfg.waveform.candidate_start_symbol,0,10,"waveform.candidate_start_symbol");
if double(cfg.waveform.candidate_start_symbol) + 4 > 14
    error("sixgr:phy:ia:c0:config:SSBOutsideSlot", ...
        "waveform.candidate_start_symbol must leave four symbols inside one slot.");
end
if ~any(double(cfg.waveform.lmax) == [4 8 64])
    error("sixgr:phy:ia:c0:config:BadLmax", ...
        "waveform.lmax must be 4, 8, or 64.");
end
if double(cfg.waveform.pbch_payload_bits) ~= 24 || ...
        double(cfg.waveform.pbch_crc_bits) ~= 24 || ...
        double(cfg.waveform.pbch_total_information_bits) ~= 56
    error("sixgr:phy:ia:c0:config:PBCHInformationContract", ...
        "C0 requires a 24-bit BCH transport block, eight added timing bits, and 24-bit CRC (56 information bits total).");
end
localInteger(cfg.waveform.mib.bcch_bch_choice_bit,0,0, ...
    "waveform.mib.bcch_bch_choice_bit");
% Reuse the central production MIB semantic validator. It owns the exact
% 23-bit field packing and rejects invalid spare/range/enumeration values.
sixgr.phy.ia.MIBSemanticValidator.resolve( ...
    "CaseID",string(cfg.meta.scenario_id), ...
    "SystemFrameNumberMSB6",double(cfg.waveform.mib.system_frame_number_msb6), ...
    "SubCarrierSpacingCommon",string(cfg.waveform.mib.subcarrier_spacing_common), ...
    "SSBSubcarrierOffset",double(cfg.waveform.mib.ssb_subcarrier_offset), ...
    "DMRSTypeAPosition",string(cfg.waveform.mib.dmrs_type_a_position), ...
    "PDCCHConfigSIB1",double(cfg.waveform.mib.pdcch_config_sib1), ...
    "CellBarred",string(cfg.waveform.mib.cell_barred), ...
    "IntraFreqReselection",string(cfg.waveform.mib.intra_freq_reselection), ...
    "Spare",double(cfg.waveform.mib.spare));
if string(cfg.channel.model) ~= "AWGN" && string(cfg.channel.delay_profile) ~= string(cfg.channel.model)
    error("sixgr:phy:ia:c0:config:ChannelProfileMismatch", ...
        "channel.delay_profile must exactly match concrete channel.model for fading C0 execution.");
end
if string(cfg.channel.model) ~= "TDL-C" || ...
        abs(double(cfg.channel.delay_spread_s)-300e-9) > eps(300e-9)*8 || ...
        double(cfg.channel.velocity_kmh) ~= 3
    error("sixgr:phy:ia:c0:config:C0ChannelContract", ...
        "C0 requires concrete TDL-C, channel.delay_spread_s=300e-9, and channel.velocity_kmh=3.");
end
localInteger(cfg.interference.interfering_trps,0,0, ...
    "interference.interfering_trps");
if any(contains(string(cfg.channel.model),["TDL" "CDL"])) && ...
        ~any(startsWith(string(cfg.channel.model),["TDL-" "CDL-"]))
    error("sixgr:phy:ia:c0:config:ConcreteProfileRequired", ...
        "Fading channel.model must be a concrete TDL-* or CDL-* profile.");
end
localInteger(cfg.mimo.num_tx_antennas,1,64,"mimo.num_tx_antennas");
localInteger(cfg.mimo.num_rx_antennas,1,64,"mimo.num_rx_antennas");
localProbability(cfg.false_alarm.target_probability,"false_alarm.target_probability");
localProbability(cfg.false_alarm.pss_stage_target_probability, ...
    "false_alarm.pss_stage_target_probability");
localInteger(cfg.false_alarm.calibration_trials,1,Inf,"false_alarm.calibration_trials");
localInteger(cfg.false_alarm.validation_trials,1,Inf,"false_alarm.validation_trials");
localInteger(cfg.false_alarm.progress_interval,1,Inf,"false_alarm.progress_interval");
localInteger(cfg.false_alarm.checkpoint_interval,1,Inf,"false_alarm.checkpoint_interval");
localInteger(cfg.run.max_trials_per_snr,1,Inf,"run.max_trials_per_snr");
localInteger(cfg.run.min_errors_per_snr,0,Inf,"run.min_errors_per_snr");
localInteger(cfg.run.seed_set_main,1,2^32-1,"run.seed_set_main");
localInteger(cfg.run.seed_set_calibration,1,2^32-1,"run.seed_set_calibration");
localInteger(cfg.run.seed_set_validation,1,2^32-1,"run.seed_set_validation");
localScalar(cfg.statistics.confidence_level,0,1,"statistics.confidence_level");
localProbability(cfg.false_alarm.relative_ci_half_width_limit, ...
    "false_alarm.relative_ci_half_width_limit");
localScalar(cfg.receiver.timing_success_tolerance_fraction_min_cp,0,1, ...
    "receiver.timing_success_tolerance_fraction_min_cp");
localScalar(cfg.search.fine_cfo.maximum_residual_hz,0, ...
    double(cfg.carrier.scs_khz)*1000/2, ...
    "search.fine_cfo.maximum_residual_hz");
localInteger(cfg.search.fine_cfo.minimum_symbols,1,4, ...
    "search.fine_cfo.minimum_symbols");
localInteger(cfg.validation.snr_calibration_repetitions,1,Inf, ...
    "validation.snr_calibration_repetitions");
localScalar(cfg.validation.snr_calibration_tolerance_db,0,1, ...
    "validation.snr_calibration_tolerance_db");
localScalar(cfg.validation.high_snr_nmse_floor_margin_db,0,20, ...
    "validation.high_snr_nmse_floor_margin_db");
localScalar(cfg.validation.fine_cfo_sigma_multiplier,0,10, ...
    "validation.fine_cfo_sigma_multiplier");
localScalar(cfg.snr.refinement_step_db,0,Inf,"snr.refinement_step_db");
if ~(isnumeric(cfg.snr.minimum_db)&&isscalar(cfg.snr.minimum_db)&& ...
        isfinite(cfg.snr.minimum_db)&&isnumeric(cfg.snr.maximum_db)&& ...
        isscalar(cfg.snr.maximum_db)&&isfinite(cfg.snr.maximum_db)&& ...
        double(cfg.snr.maximum_db)>double(cfg.snr.minimum_db))
    error("sixgr:phy:ia:c0:config:SNRRange", ...
        "snr.minimum_db and snr.maximum_db must be finite scalars with maximum_db greater than minimum_db.");
end
localValidateSeedPartitions(cfg);
if ~logical(cfg.search.fine_cfo.enabled)
    error("sixgr:phy:ia:c0:config:C0FineCFORequired", ...
        "C0 practical acquisition requires search.fine_cfo.enabled=true.");
end

if string(cfg.waveform.normalization) ~= "equal_epre" || ...
        string(cfg.receiver.practical_timing) ~= "blind" || ...
        string(cfg.receiver.practical_cfo) ~= "blind_grid" || ...
        string(cfg.receiver.practical_pci) ~= "blind_pss_sss" || ...
        string(cfg.receiver.channel_estimation) ~= "practical_pbch_dmrs"
    error("sixgr:phy:ia:c0:config:C0ReceiverContract", ...
        "C0 requires equal_epre, blind timing/CFO/PCI, and practical_pbch_dmrs channel estimation.");
end
if any(abs(double(cfg.oscillator.ue_ppm_range(:).')-[-10 10]) > eps(10)*8) || ...
        any(abs(double(cfg.oscillator.trp_ppm_range(:).')-[-0.05 0.05]) > eps(0.05)*8)
    error("sixgr:phy:ia:c0:config:C0OscillatorContract", ...
        "C0 requires oscillator.ue_ppm_range=[-10,10] and oscillator.trp_ppm_range=[-0.05,0.05].");
end
cfoGrid=double(cfg.search.cfo_hypotheses_hz(:).');
requiredCFOHz=(10+0.05)*1e-6*double(cfg.carrier.frequency_hz);
localScalar(cfg.search.cfo_coverage_margin_hz,0,Inf, ...
    "search.cfo_coverage_margin_hz");
requiredCoverageHz=requiredCFOHz+double(cfg.search.cfo_coverage_margin_hz);
if isempty(cfoGrid) || min(cfoGrid)>-requiredCoverageHz || ...
        max(cfoGrid)<requiredCoverageHz
    error("sixgr:phy:ia:c0:config:CFOCoverage", ...
        "search.cfo_hypotheses_hz must cover at least +/-%.3f Hz: %.3f-Hz oscillator uncertainty plus %.3f-Hz configured margin.", ...
        requiredCoverageHz,requiredCFOHz,double(cfg.search.cfo_coverage_margin_hz));
end
if strcmpi(string(cfg.run.mode),"tdoc") || strcmpi(string(cfg.run.mode),"exhaustive")
    if double(cfg.run.max_trials_per_snr) < 200000 || ...
            double(cfg.run.min_errors_per_snr) < 500 || ...
            double(cfg.false_alarm.calibration_trials) < 100000 || ...
            double(cfg.false_alarm.validation_trials) < 100000
        error("sixgr:phy:ia:c0:config:TDocStatisticalMinimum", ...
            "TDOC mode requires max_trials_per_snr>=200000, min_errors_per_snr>=500, and at least 100000 calibration plus 100000 validation noise windows.");
    end
end
if ~logical(cfg.output.prohibit_svg)
    error("sixgr:phy:ia:c0:config:RasterPolicy", ...
        "output.prohibit_svg must be true.");
end
end

function localValidateSeedPartitions(cfg)
capacity=double(cfg.statistics.tdoc_max_trials_per_point);
configuredSNRs=[double(cfg.snr.minimum_db) double(cfg.snr.maximum_db) ...
    double(cfg.snr.coarse_grid_db(:).') ...
    double(cfg.statistics.high_snr_sanity_db)];
seedMinimum=min(configuredSNRs); seedMaximum=max(configuredSNRs);
pointCount=round((seedMaximum-seedMinimum)/ ...
    double(cfg.snr.refinement_step_db))+1;
main=[double(cfg.run.seed_set_main)+1, ...
    double(cfg.run.seed_set_main)+pointCount*4*capacity];
calibration=[double(cfg.run.seed_set_calibration)+1, ...
    double(cfg.run.seed_set_calibration)+double(cfg.false_alarm.calibration_trials)];
validation=[double(cfg.run.seed_set_validation)+1, ...
    double(cfg.run.seed_set_validation)+double(cfg.false_alarm.validation_trials)];
ranges=[main;calibration;validation];
names=["main waveform" "false-alarm calibration" "false-alarm validation"];
if any(ranges(:)>2^32-1)
    error("sixgr:phy:ia:c0:config:SeedRangeOverflow", ...
        "C0 seed partitions must remain within MATLAB's [0,2^32-1] twister seed range; resolved ranges are %s.", ...
        localRangesText(names,ranges));
end
for first=1:size(ranges,1)
    for second=first+1:size(ranges,1)
        if max(ranges(first,1),ranges(second,1))<= ...
                min(ranges(first,2),ranges(second,2))
            error("sixgr:phy:ia:c0:config:SeedRangeOverlap", ...
                "C0 requires disjoint deterministic seed partitions; %s overlaps %s. Resolved ranges: %s.", ...
                names(first),names(second),localRangesText(names,ranges));
        end
    end
end
end

function value=localRangesText(names,ranges)
parts=strings(numel(names),1);
for k=1:numel(names)
    parts(k)=names(k)+"=["+compose("%.0f",ranges(k,1))+","+ ...
        compose("%.0f",ranges(k,2))+"]";
end
value=strjoin(parts,"; ");
end

function localEnum(cfg,path,allowed)
value = string(sixgr.util.structGet(cfg,path,""));
if ~isscalar(value) || ~any(strcmpi(value,allowed))
    error("sixgr:phy:ia:c0:config:BadEnum", ...
        "%s='%s' is unsupported; allowed values are %s.",path,value,strjoin(allowed,", "));
end
end
function localScalar(v,lo,hi,name)
if ~(isnumeric(v) && isscalar(v) && isreal(v) && isfinite(v) && v > lo && v <= hi)
    error("sixgr:phy:ia:c0:config:BadScalar", ...
        "%s must be in (%g,%g].",name,lo,hi);
end
end
function localInteger(v,lo,hi,name)
if ~(isnumeric(v) && isscalar(v) && isfinite(v) && v >= lo && v <= hi && v == round(v))
    error("sixgr:phy:ia:c0:config:BadInteger", ...
        "%s must be an integer in [%g,%g].",name,lo,hi);
end
end
function localProbability(v,name)
if ~(isnumeric(v) && isscalar(v) && isfinite(v) && v > 0 && v < 1)
    error("sixgr:phy:ia:c0:config:BadProbability", ...
        "%s must be strictly between zero and one.",name);
end
end
