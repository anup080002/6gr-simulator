function phyCfg = toPHYConfig(cfg)
%TOPHYCONFIG Adapt C0 config to the existing strict PHY facades.
phyCfg = struct();
phyCfg.run = struct("strictMode",true);
phyCfg.frequency = struct( ...
    "centerFrequency_Hz",double(cfg.carrier.frequency_hz), ...
    "center_frequency_hz",double(cfg.carrier.frequency_hz), ...
    "frequency_range_subtype","FR1");
phyCfg.phy = struct();
phyCfg.phy.sampleRate_Hz = [];
phyCfg.phy.frequencyRange = "FR1";
phyCfg.phy.carrier = struct( ...
    "NCellID",double(cfg.waveform.n_cell_id), ...
    "centerFrequency_Hz",double(cfg.carrier.frequency_hz), ...
    "SubcarrierSpacing",double(cfg.carrier.scs_khz), ...
    "SubcarrierSpacing_kHz",double(cfg.carrier.scs_khz), ...
    "CyclicPrefix",char(string(cfg.carrier.cyclic_prefix)), ...
    "NSizeGrid",double(cfg.carrier.n_size_grid), ...
    "NStartGrid",0);
phyCfg.phy.bwp = struct("dl",struct("NStartBWP",0,"NSizeBWP",double(cfg.carrier.n_size_grid)));
phyCfg.phy.ssb = struct( ...
    "enable",true, ...
    "blockPattern",char(string(cfg.waveform.block_pattern)), ...
    "scs_kHz",double(cfg.carrier.scs_khz), ...
    "Lmax",double(cfg.waveform.lmax), ...
    "periodicity_ms",20, ...
    "NCRBSSB",0, ...
    "KSSB",double(cfg.waveform.k_ssb), ...
    "activeBitmap","10000000");
phyCfg.phy.pbch = struct("enable",true);
phyCfg.phy.mib = struct("enable",true);
phyCfg.phy.sync = struct( ...
    "freqSearchBW_Hz",max(abs(double(cfg.search.cfo_hypotheses_hz))), ...
    "cfoHypothesesHz",double(cfg.search.cfo_hypotheses_hz(:).'), ...
    "nid2Hypotheses",double(cfg.search.nid2_hypotheses(:).'), ...
    "fineCFOEnabled",logical(cfg.search.fine_cfo.enabled), ...
    "fineCFOMethod",string(cfg.search.fine_cfo.method), ...
    "fineCFOMaxResidualHz",double(cfg.search.fine_cfo.maximum_residual_hz), ...
    "fineCFOMinimumSymbols",double(cfg.search.fine_cfo.minimum_symbols));
phyCfg.phy.synchronization = struct( ...
    "maxTimingUncertaintySamples",double(cfg.search.timing_uncertainty_samples));
phyCfg.receiver = cfg.receiver;
end
