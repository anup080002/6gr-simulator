function [received,noise,meta] = addNoiseForTargetSNR(cleanWaveform,bundle,activeReceivedREPower,snrDB,seed)
%ADDNOISEFORTARGETSNR Add noise using the production IA active-RE convention.
%
% SNR is average desired received SSB RE power per receive antenna divided
% by noise power per active complex RE before receiver combining.
if ~(isscalar(activeReceivedREPower) && isfinite(activeReceivedREPower) && activeReceivedREPower > 0)
    error("sixgr:phy:ia:c0:channel:InvalidReferencePower", ...
        "Active received SSB RE power must be positive and finite.");
end
cal = sixgr.phy.waveform.calibrateOFDMNoiseTransform(bundle.Carrier, ...
    "Windowing",0,"NumNoiseRE",262144,"UseCache",true);
targetGridNoiseVariance = double(activeReceivedREPower)/10^(double(snrDB)/10);
timeNoiseVariance = targetGridNoiseVariance/double(cal.SampleToGridNoiseVarianceGain);
old = rng;
cleanup = onCleanup(@()rng(old)); %#ok<NASGU>
rng(double(seed),"twister");
noise = sqrt(timeNoiseVariance/2).* ...
    (randn(size(cleanWaveform))+1j*randn(size(cleanWaveform)));
received = cleanWaveform + noise;
meta = struct( ...
    "SNRDefinition","average_desired_received_ssb_re_power_per_rx_antenna_over_noise_power_per_active_complex_re_before_combining", ...
    "RequestedSNRDB",double(snrDB), ...
    "ActiveReceivedREPower",double(activeReceivedREPower), ...
    "TargetGridNoiseVariance",double(targetGridNoiseVariance), ...
    "TimeNoiseVariance",double(timeNoiseVariance), ...
    "SampleToGridNoiseVarianceGain",double(cal.SampleToGridNoiseVarianceGain), ...
    "CalibrationSource",string(cal.Source), ...
    "NoiseSeed",double(seed));
end
