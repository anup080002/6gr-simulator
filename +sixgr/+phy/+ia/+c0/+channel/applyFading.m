function result = applyFading(txWaveform,bundle,cfg,seed)
%APPLYFADING Apply the configured production waveform-domain C0 channel.
model = upper(strtrim(string(cfg.channel.model)));
nTx = double(cfg.mimo.num_tx_antennas);
nRx = double(cfg.mimo.num_rx_antennas);
weights = ones(1,nTx)/sqrt(nTx);
txPorts = txWaveform(:)*weights;
if model == "AWGN"
    result = struct( ...
        "Waveform",repmat(txWaveform(:),1,nRx), ...
        "TimingOffsetSamples",0, ...
        "PathGains",[], ...
        "PathFilters",[], ...
        "SampleTimes",[], ...
        "MaximumDopplerHz",0, ...
        "ExecutionBackend","unit_channel_awgn", ...
        "ApproximationMode","none");
    return;
end
if model ~= "TDL-C"
    error("sixgr:phy:ia:c0:channel:UnsupportedPhase1Channel", ...
        "Phase-1 C0 supports only TDL-C and the explicit AWGN calibration path; got %s.",model);
end
channel = nrTDLChannel;
channel.DelayProfile = char(model);
channel.DelaySpread = double(cfg.channel.delay_spread_s);
channel.MaximumDopplerShift = double(cfg.channel.velocity_kmh)/3.6* ...
    double(cfg.carrier.frequency_hz)/physconst("LightSpeed");
channel.SampleRate = double(bundle.SampleRateHz);
channel.NumTransmitAntennas = nTx;
channel.NumReceiveAntennas = nRx;
channel.NormalizePathGains = logical(cfg.channel.normalize_path_gains);
channel.NormalizeChannelOutputs = logical(cfg.channel.normalize_channel_outputs);
% R2026a replaced PathGainsOutputPort with ChannelResponseOutput. Preserve
% the same physical path-gain output on both the current and prior APIs.
if isprop(channel,"ChannelResponseOutput")
    channel.ChannelResponseOutput = "path-gains";
elseif isprop(channel,"PathGainsOutputPort")
    channel.PathGainsOutputPort = true;
else
    error("sixgr:phy:ia:c0:channel:PathGainOutputUnavailable", ...
        "The installed nrTDLChannel exposes no physical path-gain output.");
end
channel.RandomStream = "mt19937ar with seed";
channel.Seed = double(seed);
channelInfo = info(channel);
pad = double(channelInfo.MaximumChannelDelay);
[rx,pathGains,sampleTimes] = channel([txPorts;zeros(pad,nTx)]);
pathFilters = getPathFilters(channel);
timing = double(nrPerfectTimingEstimate(pathGains,pathFilters));
if ~(isscalar(timing) && isfinite(timing) && timing >= 0)
    error("sixgr:phy:ia:c0:channel:TimingUnavailable", ...
        "nrPerfectTimingEstimate did not return a valid channel-delay reference.");
end
result = struct( ...
    "Waveform",rx, ...
    "TimingOffsetSamples",timing, ...
    "PathGains",pathGains, ...
    "PathFilters",pathFilters, ...
    "SampleTimes",sampleTimes, ...
    "MaximumDopplerHz",double(channel.MaximumDopplerShift), ...
    "ExecutionBackend","nrTDLChannel", ...
    "ApproximationMode","none");
end
