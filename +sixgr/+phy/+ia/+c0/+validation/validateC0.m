function [gates,summary] = validateC0(cfg,bundle,calibration,faValidation,raw,points,crossings,zeroAnchor,lineage)
%VALIDATEC0 Apply the production Phase-1 fail-closed truth contract.
mode=lower(string(cfg.run.mode));
isTDoc=any(mode==["tdoc" "exhaustive"]);
high=points(points.SNRDB==max(points.SNRDB),:);
snrError=max(abs(points.MeanMeasuredInputSNRDB-points.SNRDB));
oracleNotWorse=all(points.OracleCompleteSSBSuccessProbability+1e-12 >= points.CompleteSSBSuccessProbability);
rawCountsOk=height(raw)>0 && all(points.Trials>0) && sum(points.Trials)==height(raw);
allBracketed=all(crossings.Bracketed);
noSynthetic=all(raw.EvidenceClass=="actual_nr_ssb_waveform_receiver_truth") && ...
    all(raw.ApproximationMode=="none");
ids=("PASS-"+compose("%03d",(1:15)')).';
names=["waveform_resource_map_valid";"energy_normalization_closes"; ...
    "requested_snr_calibrated";"global_false_alarm_ci_contains_target"; ...
    "pbch_high_snr_decode";"wrong_pci_high_snr_zero"; ...
    "zero_impairment_timing_cfo";"oracle_not_worse"; ...
    "equal_resource_audit";"random_arrival_schedule_cdf"; ...
    "papr_oversampling";"qcw_boundary";"raw_counts_for_every_curve"; ...
    "target_crossings_bracketed";"no_synthetic_datapoints"];
applicable=[true;true;true;true;true;true;true;true;false;false;false;false;true;isTDoc;true];
pass=[bundle.ResourceAudit.ActiveRE==nnz(bundle.SSBGrid); ...
    abs(bundle.ResourceAudit.Normalization.ClosureDB)<0.01;snrError<=0.1;logical(faValidation.Passed); ...
    high.OracleCompleteSSBSuccessProbability>=0.9;high.WrongPCIProbability==0; ...
    logical(zeroAnchor.CompleteSSBSuccess)&&abs(zeroAnchor.TimingErrorSamples)<=1&&abs(zeroAnchor.CFOErrorHz)<=1; ...
    oracleNotWorse;true;true;true;true;rawCountsOk;allBracketed;noSynthetic];
pass(~applicable)=true;
status=repmat("PASS",15,1); status(~applicable)="NOT_APPLICABLE_PHASE_1";
status(applicable&~pass)="FAIL";
details=["active_re="+bundle.ResourceAudit.ActiveRE;"closure_db="+bundle.ResourceAudit.Normalization.ClosureDB; ...
    "max_mean_error_db="+snrError;"pfa="+faValidation.EmpiricalPFA+" ci=["+faValidation.CILow+","+faValidation.CIHigh+"]"; ...
    "oracle_high_snr_success="+high.OracleCompleteSSBSuccessProbability; ...
    "wrong_pci_high_snr="+high.WrongPCIProbability; ...
    "timing_error="+zeroAnchor.TimingErrorSamples+" cfo_error_hz="+zeroAnchor.CFOErrorHz; ...
    "oracle_not_worse="+oracleNotWorse;"single_candidate_C0";"phase_3_scope"; ...
    "phase_6_scope";"phase_10_scope";"raw_trials="+height(raw); ...
    "bracketed="+nnz(crossings.Bracketed)+"/"+height(crossings); ...
    "lineage_rows="+height(lineage)];
gates=table(ids(:),names,applicable,pass,status,details, ...
    'VariableNames',{'GateID','Check','Applicable','Pass','Status','Details'});
coreMask=applicable;
if ~isTDoc, coreMask=coreMask & ids(:)~="PASS-014"; end
summary=struct("SmokeOrEngineeringPass",all(pass(coreMask)), ...
    "TDocPass",isTDoc&&all(pass(applicable)), ...
    "ApplicableGateCount",nnz(applicable),"PassedApplicableGates",nnz(pass&applicable));
end
