function [gates,summary] = validateC0(cfg,bundle,calibration,faValidation, ...
        raw,points,crossings,zeroAnchor,lineage,ceUnitTests,snrCalibration)
%VALIDATEC0 Apply C0-G01 through C0-G20 without proxy evidence.
mode=lower(string(cfg.run.mode)); isTDoc=any(mode==["tdoc" "exhaustive"]);
high=points(points.SNRDB==double(cfg.statistics.high_snr_sanity_db),:);
if height(high)~=1
    error("sixgr:phy:ia:c0:validation:MissingHighSNRSanityPoint", ...
        "Expected exactly one simulated high-SNR sanity point at %.3f dB; found %d.", ...
        double(cfg.statistics.high_snr_sanity_db),height(high));
end
finiteNMSE=points(isfinite(points.ChannelEstimateNMSEDB),:);
if isempty(finiteNMSE), low=points(1,:); else, low=finiteNMSE(1,:); end

declarationPartition=all(double(raw.NoCellDeclared)+ ...
    double(raw.CorrectPCIDeclared)+double(raw.WrongPCIDeclared)==1);
joint=raw.CellDeclared&raw.PSSIdentityCorrect&raw.SSSCorrect;
completeAccounting=all(raw.CompleteSSBSuccess<=joint)&& ...
    all(raw.PBCHConditionalAttempted==joint)&& ...
    nnz(raw.CompleteSSBSuccess)+nnz(~raw.CompleteSSBSuccess)==height(raw);
componentIndependent=all(raw.PBCHComponentAttempted)&& ...
    all(points.PBCHComponentTrials==points.Trials);
componentRows=startsWith(crossings.Label,"gamma_SS_")| ...
    startsWith(crossings.Label,"gamma_PBCH_");
qualifiedBrackets=all(crossings.Bracketed(componentRows))&& ...
    all(crossings.LowerErrors(componentRows)>=double(cfg.run.min_errors_per_snr)| ...
    crossings.LowerTrials(componentRows)>=double(cfg.run.max_trials_per_snr))&& ...
    all(crossings.UpperErrors(componentRows)>=double(cfg.run.min_errors_per_snr)| ...
    crossings.UpperTrials(componentRows)>=double(cfg.run.max_trials_per_snr));
gammaConfidence=all(crossings.Bracketed)&& ...
    all(isfinite(crossings.CrossingCILowDB))&& ...
    all(isfinite(crossings.CrossingCIHighDB));
timingPopulation=all(raw.TimingValidPopulation== ...
    (joint&raw.CorrectOccurrence))&&high.TimingValidTrials>0;
cfoTruth=max(abs(raw.AppliedCFOHz-(raw.TRPOscillatorHz-raw.UEOscillatorHz)))<1e-9;

nfft=double(bundle.OFDMInfo.Nfft);
minimumCP=min(double(bundle.OFDMInfo.SymbolLengths(:)))-nfft;
products=max(1,4*minimumCP*double(cfg.mimo.num_rx_antennas));
estimatorSigma=bundle.SampleRateHz/(2*pi*nfft)*sqrt( ...
    1/(2*products*10^(double(high.SNRDB)/10)));
doppler=double(cfg.channel.velocity_kmh)/3.6*double(cfg.carrier.frequency_hz)/physconst("LightSpeed");
expectedCFOFloor=sqrt(estimatorSigma^2+doppler^2);
cfoFloorLimit=double(cfg.validation.fine_cfo_sigma_multiplier)*expectedCFOFloor;
cfoFloorPass=isfinite(high.CFORMSEHz)&&high.CFORMSEHz<=cfoFloorLimit;

ce3=ceUnitTests(ceUnitTests.UnitTest=="CE-UT3",:);
ce4=ceUnitTests(ceUnitTests.UnitTest=="CE-UT4",:);
if height(ce4)==1&&isfinite(ce4.MeasuredValue)&&ce4.MeasuredValue>0
    highSNRReferenceDB=10*log10(ce4.MeasuredValue);
else
    highSNRReferenceDB=NaN;
end
nmseTrend=isfinite(high.ChannelEstimateNMSEDB)&& ...
    high.ChannelEstimateNMSEDB<low.ChannelEstimateNMSEDB&&height(ce3)==1&& ...
    height(ce4)==1&&isfinite(highSNRReferenceDB)&& ...
    high.ChannelEstimateNMSEDB<=highSNRReferenceDB+ ...
    double(cfg.validation.high_snr_nmse_floor_margin_db);
rawCounts=height(raw)>0&&sum(points.Trials)==height(raw)&& ...
    all(points.Trials>0)&&all(points.PBCHComponentTrials==points.Trials);
ids="C0-G"+compose("%02d",(1:20)');
names=["requested_actual_snr";"calibration_noise_windows"; ...
    "validation_noise_windows";"global_false_alarm_precision"; ...
    "all_target_crossings_bracketed";"target_points_stopping_rule"; ...
    "wrong_pci_accounting";"high_snr_wrong_pci"; ...
    "pbch_component_population_independence";"complete_ssb_accounting"; ...
    "timing_valid_population";"timing_cdf_not_pooled"; ...
    "cfo_truth_convention";"high_snr_cfo_floor"; ...
    "cfo_cdf_not_pooled";"pbch_ce_ut1_ut6"; ...
    "pbch_nmse_trend_and_floor";"pbch_high_snr_clean_decode"; ...
    "raw_counters_for_every_point";"gamma_confidence_reproducible"];
pass=[all(snrCalibration.Pass);calibration.TrialCount>=100000&& ...
    calibration.ReceiverExceptionCount==0; ...
    faValidation.TrialCount>=100000&&faValidation.ReceiverExceptionCount==0&& ...
    faValidation.IndependentFromCalibration; ...
    logical(faValidation.Passed)&&faValidation.IndependentFromCalibration; ...
    all(crossings.Bracketed);qualifiedBrackets;declarationPartition; ...
    high.WrongPCIProbability==0&&high.Trials>=double(cfg.run.max_trials_per_snr); ...
    componentIndependent;completeAccounting;timingPopulation; ...
    any(lineage.FigureID=="C0_F09_timing_error_cdf_selected_snr"); ...
    cfoTruth;cfoFloorPass; ...
    any(lineage.FigureID=="C0_F11_cfo_error_cdf_selected_snr"); ...
    all(ceUnitTests.Pass);nmseTrend;logical(zeroAnchor.PBCHComponentOk); ...
    rawCounts;gammaConfidence];
applicable=true(20,1);
if ~isTDoc
    applicable([2 3 4 5 6 8 20])=false;
end
status=repmat("PASS",20,1);
status(~applicable)="BLOCKED_UNTIL_TDOC_MODE";
status(applicable&~pass)="FAIL";
details=[ ...
    "max_error_db="+max(abs(snrCalibration.ErrorDB)); ...
    "calibration_windows="+calibration.TrialCount+" seeds=["+calibration.SeedFirst+","+calibration.SeedLast+"] exceptions="+calibration.ReceiverExceptionCount; ...
    "validation_windows="+faValidation.TrialCount+" seeds=["+faValidation.SeedFirst+","+faValidation.SeedLast+"] independent="+faValidation.IndependentFromCalibration+" exceptions="+faValidation.ReceiverExceptionCount; ...
    "pfa="+faValidation.EmpiricalPFA+" ci=["+faValidation.CILow+","+faValidation.CIHigh+"] relative_half_width="+faValidation.RelativeCIHalfWidth+" independent="+faValidation.IndependentFromCalibration; ...
    "bracketed="+nnz(crossings.Bracketed)+"/"+height(crossings); ...
    "qualified_component_brackets="+qualifiedBrackets; ...
    "declaration_partition="+declarationPartition; ...
    "high_snr_wrong="+high.WrongPCIErrors+"/"+high.Trials; ...
    "component_trials="+sum(points.PBCHComponentTrials)+" total_trials="+sum(points.Trials); ...
    "complete_accounting="+completeAccounting; ...
    "timing_valid_high_snr="+high.TimingValidTrials; ...
    "selected_snr_timing_cdf=true"; ...
    "max_cfo_truth_error_hz="+max(abs(raw.AppliedCFOHz-(raw.TRPOscillatorHz-raw.UEOscillatorHz))); ...
    "measured_rmse_hz="+high.CFORMSEHz+" derived_limit_hz="+cfoFloorLimit; ...
    "selected_snr_cfo_cdf=true"; ...
    "ce_pass="+nnz(ceUnitTests.Pass)+"/"+height(ceUnitTests); ...
    "low_nmse_db="+low.ChannelEstimateNMSEDB+" high_nmse_db="+high.ChannelEstimateNMSEDB+" matched_high_snr_reference_db="+highSNRReferenceDB+" no_noise_floor_db="+ce3.MeasuredValue; ...
    "zero_anchor_component_pbch="+zeroAnchor.PBCHComponentOk; ...
    "raw_trials="+height(raw)+" points="+height(points); ...
    "gamma_ci_rows="+nnz(isfinite(crossings.CrossingCILowDB))+"/"+height(crossings)];
gates=table(ids,names,applicable,logical(pass),status,details, ...
    'VariableNames',{'GateID','Check','Applicable','Pass','Status','Details'});
summary=struct("SmokeOrEngineeringPass",all(pass(applicable)), ...
    "TDocPass",isTDoc&&all(pass),"ApplicableGateCount",nnz(applicable), ...
    "PassedApplicableGates",nnz(pass&applicable));
end
