        setupTx.Waveform, appliedSNR, ...
        "SignalPower", mean(abs(setupTx.Waveform(:)).^2));
    [setupRx, setupCompleteRx] = ...
        sixgr.phy.ra.recoverRRCSetupComplete( ...
        setupWave, cfg, raCfg, setupTx);
    setupOK = logical(sixgr.util.structGet(setupRx, "Ok", false)) && ...
        ~isempty(fieldnames(setupCompleteRx)) && ...
        string(setupCompleteRx.PayloadHash) == ...
        string(setupCompleteTx.PayloadHash);
    if ~setupOK
        error("sixgr:phy:ia:RRCSetupCompleteFailure", ...
            "RRCSetupComplete waveform trial %d failed.", ii);
    end
    state = sixgr.phy.ia. ...
        RRCConnectionEstablishmentStateMachine.execute( ...
        "CaseID", attemptID, ...
