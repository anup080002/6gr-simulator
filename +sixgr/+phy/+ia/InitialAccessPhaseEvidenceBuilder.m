function [lower, upper] = localWilsonInterval(errors, trials, confidence)
trials = double(trials);
errors = double(errors);
if trials <= 0
    lower = NaN;
    upper = NaN;
    return;
end
p = errors / trials;
alpha = 1 - double(confidence);
z = -sqrt(2) * erfcinv(2 * (1 - alpha / 2));
denominator = 1 + z^2 / trials;
center = (p + z^2 / (2 * trials)) / denominator;
half = z * sqrt((p * (1 - p) + z^2 / ...
    (4 * trials)) / trials) / denominator;
lower = max(0, center - half);
upper = min(1, center + half);
end

