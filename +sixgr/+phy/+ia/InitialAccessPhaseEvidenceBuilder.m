    % This vector contains quoted ASN.1 semantic JSON with many commas and
    % a URL colon. detectImportOptions misidentifies its header on some
    % MATLAB releases, while explicit comma parsing handles RFC-4180 quotes.
    tableOut = readtable(path, ...
        "TextType", "string", ...
        "VariableNamingRule", "preserve", ...
        "Delimiter", ",");
    for name = string(tableOut.Properties.VariableNames)
        tableOut.(char(name)) = string(tableOut.(char(name)));
    end
else
    % Force string types so leading-zero normative bit strings (MIB,
    % bitmaps, and masks) are not coerced to numbers and corrupted.
    options = detectImportOptions(path, ...
        "TextType", "string", "VariableNamingRule", "preserve");
    options = setvartype(options, options.VariableNames, "string");
    tableOut = readtable(path, options);
end
end

