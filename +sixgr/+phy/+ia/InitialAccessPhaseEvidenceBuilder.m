function bits = localHexToBits(hex)
bytes = uint8(sscanf(char(hex), "%2x"));
bits = zeros(numel(bytes) * 8, 1, "int8");
for ii = 1:numel(bytes)
    for jj = 1:8
        bits((ii - 1) * 8 + jj) = int8( ...
            bitget(bytes(ii), 9 - jj));
    end
end
end

function hash = localNumericSHA(value)
numeric = double(value(:));
realBytes = typecast(real(numeric), "uint8");
imagBytes = typecast(imag(numeric), "uint8");
shapeBytes = typecast(uint64(size(value)), "uint8");
hash = string(sixgr.util.sha256Hex( ...
    [shapeBytes(:); realBytes(:); imagBytes(:)]));
end

