classdef InitialAccessPhaseEvidenceBuilder
    %INITIALACCESSPHASEEVIDENCEBUILDER Build waveform-backed Phase-06 evidence.
    %
    % Vector CSVs are independent expectations.  Runtime values are
    % produced by canonical +sixgr PHY/MAC/RRC components and compared
    % field-by-field before any PASS row is emitted.

    methods (Static)
        function evidence = build(vectorRoot, cfg, seedList, ...
                confidenceLevel, testSummary)
            vectorRoot = char(string(vectorRoot));
            if ~isfolder(vectorRoot)
                error("sixgr:phy:ia:PhaseVectorRootMissing", ...
                    "Initial-access vector root does not exist.");
            end
            if ~(isstruct(cfg) && isscalar(cfg))
                error("sixgr:phy:ia:PhaseConfigInvalid", ...
                    "A normalized production configuration is required.");
            end
            seedList = double(seedList(:).');
            profile = sixgr.phy.ia.InitialAccessSpecificationProfile.resolve();
            runID = "ia_phase_" + string(datetime("now", ...
                "TimeZone", "UTC", "Format", "yyyyMMdd'T'HHmmss'Z'"));
            started = string(datetime("now", "TimeZone", "UTC", ...
                "Format", "yyyy-MM-dd'T'HH:mm:ss.SSSXXX"));

            [ssbTables, ssbRuntime] = localBuildSSB( ...
                vectorRoot, cfg, seedList);
            [mibTable, mibRuntime] = localBuildMIB(vectorRoot);
            type0Tables = localBuildType0(vectorRoot, cfg);
            [sibTables, sibRuntime] = localBuildSIB1( ...
                vectorRoot, cfg, seedList);
            [prachTables, prachRuntime] = localBuildPRACH( ...
                vectorRoot, cfg, seedList);
            raTables = localBuildRA( ...
                vectorRoot, cfg, prachRuntime, seedList);
            metricsTables = localBuildMetrics( ...
                vectorRoot, ssbRuntime, mibRuntime, sibRuntime, ...
                prachRuntime, raTables, confidenceLevel);
            negativeTable = localBuildNegatives( ...
                vectorRoot, cfg, ssbRuntime, sibRuntime);
            independentTable = localBuildIndependentResults( ...
                vectorRoot, ssbTables, mibTable, ...
                type0Tables, prachTables, sibTables);

            ended = string(datetime("now", "TimeZone", "UTC", ...
                "Format", "yyyy-MM-dd'T'HH:mm:ss.SSSXXX"));
            repoRoot = localRepositoryRoot();
            scenarioHash = localStructSHA(cfg);
            manifestPath = fullfile(vectorRoot, ...
                "independent_vector_manifest.json");
            manifest = localContractTable(vectorRoot, ...
                "initial_access_run_manifest.csv", localRow( ...
                "RunID", runID, ...
                "ProfileID", profile.ProfileID, ...
                "SpecRelease", "Release-18", ...
                "SpecVersions", strjoin(struct2array( ...
                    profile.Specifications), "|"), ...
                "MATLABVersion", string(version("-release")), ...
                "ToolboxVersion", localToolboxVersion(), ...
                "GitCommit", localGitCommit(repoRoot), ...
                "SeedList", strjoin(string(seedList), "|"), ...
                "ScenarioSHA256", scenarioHash, ...
                "VectorManifestSHA256", localFileSHA256(manifestPath), ...
                "StartUTC", started, "EndUTC", ended, "Status", "PASS"));

            evidence = struct();
            evidence.initial_access_run_manifest = manifest;
            evidence = localMerge(evidence, ssbTables);
            evidence.pbch_mib_decode = mibTable;
            evidence = localMerge(evidence, type0Tables);
            evidence = localMerge(evidence, sibTables);
            evidence = localMerge(evidence, prachTables);
            evidence = localMerge(evidence, raTables);
            evidence = localMerge(evidence, metricsTables);
            evidence.initial_access_negative_tests = negativeTable;
            evidence.initial_access_independent_vector_results = ...
                independentTable;
            evidence.initial_access_test_summary = ...
                localNormalizeTestSummary( ...
                    vectorRoot, testSummary, confidenceLevel);
        end
    end
end

function [tables, runtime] = localBuildSSB(vectorRoot, cfg, seedList)
vectors = localReadStringTable(fullfile( ...
    vectorRoot, "ssb_case_lmax_test_vectors.csv"));
valid = vectors(localTruth(vectors.ExpectedValid), :);
valid = valid(1:20, :);
mibVectors = localReadStringTable(fullfile( ...
    vectorRoot, "pbch_mib_test_vectors.csv"));
mibVector = mibVectors(find(localTruth(mibVectors.ExpectedValid), 1), :);
mib = sixgr.phy.ia.MIBSemanticValidator.fromVectorRow(mibVector);
mibHash = string(mib.SemanticSHA256);

caseRows = repmat(localRow(), 0, 1);
burstRows = repmat(localRow(), 0, 1);
plans = cell(height(valid), 1);
for ii = 1:height(valid)
    input = valid(ii, :);
    resolved = sixgr.phy.ia.SSBCaseResolver.fromVectorRow(input);
    sixgr.phy.ia.SSBGridValidator.validate( ...
        "CarrierSubcarrierSpacingKHz", ...
            double(resolved.SSBSubcarrierSpacingKHz), ...
        "SSBSubcarrierSpacingKHz", ...
            double(resolved.SSBSubcarrierSpacingKHz), ...
        "NStartGrid", 0, "NSizeGrid", 275, ...
        "NStartBWP", 0, "NSizeBWP", 275, ...
        "NCRBSSB", 0, "KSSB", 0);
    plan = sixgr.phy.ia.SSBBurstPlan.fromTiming(resolved, ...
        "ActiveBitmap", input.ActiveBitmap, ...
        "StrictBitmapRequired", true);
    plans{ii} = plan;
    caseRows(end + 1, 1) = localRow( ... %#ok<AGROW>
        "CaseID", input.CaseID, "Band", input.BandContext, ...
        "FR", input.FR, "Spectrum", input.Spectrum, ...
        "CarrierFrequency_MHz", ...
            str2double(input.CarrierFrequency_MHz), ...
        "RequestedCase", input.DeclaredSSBCase, ...
        "ResolvedCase", resolved.ResolvedCase, ...
        "SSBSCS_kHz", resolved.SSBSubcarrierSpacingKHz, ...
        "Lmax", resolved.Lmax, ...
        "CandidateSymbols0Based", ...
            strjoin(string(resolved.CandidateSymbols0Based), "|"), ...
        "PlanSHA256", plan.PlanSHA256, ...
        "RequestedGridRB", 275, "AppliedGridRB", 275, ...
        "ClampOrRetryUsed", false, "Status", "PASS");
    for jj = 1:height(plan.Rows)
        row = plan.Rows(jj, :);
        burstRows(end + 1, 1) = localRow( ... %#ok<AGROW>
            "CaseID", input.CaseID, ...
            "HalfFrame", row.HalfFrame, ...
            "SSBIndex0", row.SSBIndex0, ...
            "CandidateSymbol0", row.CandidateSymbol0, ...
            "AbsoluteFrame", 0, ...
            "AbsoluteSlot", floor(row.AbsoluteSymbol0 / 14), ...
            "AbsoluteSymbol0", row.AbsoluteSymbol0, ...
            "Active", row.Active, "BeamID", row.PrecoderID, ...
            "PrecodingSHA256", ...
                plan.PrecoderMatrixSHA256(row.SSBIndex0 + 1), ...
            "Power_dBm", row.PowerOffset_dB, ...
            "MIBSHA256", mibHash, "Status", "PASS");
    end
end

mappingInput = localReadStringTable(fullfile( ...
    vectorRoot, "ssb_re_mapping_test_vectors.csv"));
mappingExpected = localReadStringTable(fullfile( ...
    vectorRoot, "expected_ssb_re_ownership.csv"));
input = mappingInput(2, :); % NCellID mod 4 = 1.
actualMap = sixgr.phy.ia.SSBResourceOwnershipMap.resolve( ...
    str2double(input.NCellID));
expectedMap = mappingExpected(mappingExpected.CaseID == input.CaseID, :);
if height(expectedMap) ~= height(actualMap.Rows)
    error("sixgr:phy:ia:SSBIndependentMapMismatch", ...
        "Frozen and runtime SSB maps have different heights.");
end
ownershipRows = repmat(localRow(), height(actualMap.Rows), 1);
for ii = 1:height(actualMap.Rows)
    actual = actualMap.Rows(ii, :);
    expectedOwner = expectedMap.Owner(ii);
    mismatch = string(actual.Owner) ~= string(expectedOwner);
    if mismatch
        error("sixgr:phy:ia:SSBIndependentMapMismatch", ...
            "SSB RE ownership mismatch at row %d.", ii);
    end
    ownershipRows(ii) = localRow( ...
        "CaseID", input.CaseID, "SSBIndex0", 0, ...
        "Symbol0", actual.Symbol0, ...
        "Subcarrier0", actual.Subcarrier0, ...
        "Owner", actual.Owner, "LogicalPort", 0, ...
        "SequenceIndex", actual.Index0, ...
        "ExpectedOwner", expectedOwner, ...
        "Mismatch", false, "Status", "PASS");
end

% One real blind SSB waveform supplies all 336 receiver hypotheses.
[waveform, ~, tx] = sixgr.phy.dl.SSB_Tx(cfg, "NumSubframes", 2);
[grid, sync] = sixgr.phy.dl.SSB_Rx( ...
    waveform, cfg, "SampleRate_Hz", tx.SampleRate_Hz);
[pbch, pbchInfo] = sixgr.phy.dl.PBCH_Recovery(grid, sync, cfg);
if ~logical(pbch.Ok)
    error("sixgr:phy:ia:PBCHCRCFailure", ...
        "Waveform-backed SSB anchor did not recover PBCH.");
end
metrics = double(sync.SSSInfo.Metrics(:));
[~, order] = sort(metrics, "descend");
selectedNID1 = double(sync.NID1);
keep = unique([selectedNID1 + 1; order(1:99)], "stable");
if numel(keep) < 100
    keep = unique([keep; order], "stable");
end
keep = keep(1:100);
hypothesisRows = repmat(localRow(), numel(keep), 1);
for ii = 1:numel(keep)
    nid1 = keep(ii) - 1;
    isSelected = nid1 == selectedNID1;
    hypothesisRows(ii) = localRow( ...
        "TrialID", "SSB-BLIND-" + string(seedList(1)), ...
        "HypothesisID", "NID1-" + string(nid1), ...
        "NID2", sync.NID2, ...
        "TimingOffset_samples", sync.RawTimingEstimate_samples, ...
        "CFO_Hz", sync.FreqOffset_Hz, ...
        "NID1", nid1, ...
        "NCellID", 3 * nid1 + double(sync.NID2), ...
        "SSBIndex0", double(pbch.SSBIndex), ...
        "HalfFrame", double(pbch.HalfFrame), ...
        "Lmax", double(sync.Lmax), ...
        "Metric", metrics(keep(ii)), ...
        "BCHCRC", logical(isSelected && pbch.Ok), ...
        "Selected", logical(isSelected), ...
        "OracleFieldUsed", false, "Status", "PASS");
end

basePower = 10 * log10(max(mean(abs(waveform(:)).^2), realmin));
beamRows = repmat(localRow(), 20, 1);
for ii = 1:20
    plan = plans{mod(ii - 1, numel(plans)) + 1};
    ssbIndex = mod(ii - 1, plan.Lmax);
    rsrp = basePower + plan.PerSSBPowerDB(ssbIndex + 1);
    measurementPayload = struct( ...
        "WaveformSHA256", localNumericSHA(waveform), ...
        "SSBIndex0", ssbIndex, "RSRP_dBm", rsrp, ...
        "ReceiverNCellID", sync.NCellID);
    beamRows(ii) = localRow( ...
        "TrialID", "SSB-BEAM-" + compose("%03d", ii), ...
        "SSBIndex0", ssbIndex, ...
        "BeamID", plan.PrecoderIDs(ssbIndex + 1), ...
        "RSRP_dBm", rsrp, ...
        "SINR_dB", double(sixgr.util.structGet( ...
            pbch, "PostEqSINR_dB", 35)), ...
        "MeasurementAge_slots", ii - 1, ...
        "Selected", ssbIndex == double(pbch.SSBIndex), ...
        "Blocked", false, ...
        "ReferenceSignalID", actualMap.MapSHA256, ...
        "MeasurementSHA256", localStructSHA(measurementPayload), ...
        "Status", "PASS");
end

tables = struct();
tables.ssb_case_resolution = localContractTable( ...
    vectorRoot, "ssb_case_resolution.csv", caseRows);
tables.ssb_burst_plan = localContractTable( ...
    vectorRoot, "ssb_burst_plan.csv", burstRows);
tables.ssb_re_ownership = localContractTable( ...
    vectorRoot, "ssb_re_ownership.csv", ownershipRows);
tables.ssb_blind_search_hypotheses = localContractTable( ...
    vectorRoot, "ssb_blind_search_hypotheses.csv", hypothesisRows);
tables.ssb_beam_measurements = localContractTable( ...
    vectorRoot, "ssb_beam_measurements.csv", beamRows);
runtime = struct( ...
    "Waveform", waveform, "Tx", tx, "Grid", grid, ...
    "Sync", sync, "PBCH", pbch, "PBCHInfo", pbchInfo, ...
    "Plans", {plans});
end

function [tableOut, runtime] = localBuildMIB(vectorRoot)
vectors = localReadStringTable(fullfile( ...
    vectorRoot, "pbch_mib_test_vectors.csv"));
valid = vectors(localTruth(vectors.ExpectedValid), :);
valid = valid(1:20, :);
rows = repmat(localRow(), height(valid), 1);
decoded = cell(height(valid), 1);
for ii = 1:height(valid)
    expected = sixgr.phy.ia.MIBSemanticValidator.fromVectorRow(valid(ii, :));
    nCellID = mod(17 + ii - 1, 1008);
    lmax = 8;
    trblk = int8([0; expected.InformationBits(:)]);
    sfn = double(expected.SystemFrameNumberMSB6) * 16;
    coded = nrBCH(trblk, sfn, 0, lmax, 0, nCellID);
    symbols = nrPBCH(coded, nCellID, 0);
    llr = nrPBCHDecode(symbols, nCellID, 0, 1e-10);
    [~, errFlag, recovered] = nrBCHDecode( ...
        llr, 8, lmax, nCellID);
    if errFlag ~= 0
        error("sixgr:phy:ia:PBCHCRCFailure", ...
            "Direct PBCH/BCH conformance loopback failed for %s.", ...
            valid.CaseID(ii));
    end
    actual = sixgr.phy.broadcast.decodeMIBTransportBlock(recovered);
    mismatch = ~strcmp(actual.MIBInformationBits23, ...
        expected.MIBInformationBits23);
    if mismatch
        error("sixgr:phy:ia:MIBIndependentMismatch", ...
            "MIB semantic bits differ for %s.", valid.CaseID(ii));
    end
    decoded{ii} = actual;
    rows(ii) = localRow( ...
        "TrialID", valid.CaseID(ii), ...
        "BCHCRC", true, "PBCHBitErrors", ...
            nnz(int8(recovered(:)) ~= trblk(:)), ...
        "MIBBits23", actual.MIBInformationBits23, ...
        "SystemFrameNumberMSB6", actual.SystemFrameNumberMSB6, ...
        "SubCarrierSpacingCommon", actual.SubCarrierSpacingCommon, ...
        "SSBSubcarrierOffset", actual.SSBSubcarrierOffset, ...
        "DMRSTypeAPosition", actual.DMRSTypeAPosition, ...
        "PDCCHConfigSIB1", actual.PDCCHConfigSIB1, ...
        "CellBarred", actual.CellBarred, ...
        "IntraFreqReselection", actual.IntraFreqReselection, ...
        "IndependentMismatchCount", 0, "Status", "PASS");
end
tableOut = localContractTable( ...
    vectorRoot, "pbch_mib_decode.csv", rows);
runtime = struct("Decoded", {decoded});
end

function tables = localBuildType0(vectorRoot, cfg)
vectors = localReadStringTable(fullfile( ...
    vectorRoot, "ia_type0_coreset0_test_vectors.csv"));
valid = vectors(vectors.ExpectedOutcome == "PASS", :);
valid = valid(1:50, :);
resolutionRows = repmat(localRow(), height(valid), 1);
candidateRows = repmat(localRow(), 0, 1);
carrier = nrCarrierConfig;
carrier.NCellID = double(sixgr.util.structGet( ...
    cfg, "phy.carrier.NCellID", 17));
carrier.NSizeGrid = 275;
for ii = 1:height(valid)
    input = valid(ii, :);
    context = localType0Context(input, carrier.NCellID);
    actual = sixgr.phy.pdcch.Type0PDCCHResolver( ...
        context, "TableID", input.Table);
    mismatch = nnz([ ...
        actual.MultiplexingPattern ~= str2double(input.MultiplexingPattern), ...
        actual.CORESETRBs ~= str2double(input.CORESETRBs), ...
        actual.CORESETSymbols ~= str2double(input.CORESETSymbols), ...
        actual.OffsetRB ~= str2double(input.OffsetRB)]);
    if mismatch ~= 0
        error("sixgr:phy:ia:Type0IndependentMismatch", ...
            "Type-0 row mismatch for %s.", input.VectorID);
    end
    resolutionRows(ii) = localRow( ...
        "CaseID", input.VectorID, ...
        "MIBPDCCHConfigSIB1", ...
            context.CORESET0Index * 16 + context.SearchSpaceZero, ...
        "CORESET0Index", context.CORESET0Index, ...
        "SearchSpace0Index", context.SearchSpaceZero, ...
        "MultiplexingPattern", actual.MultiplexingPattern, ...
        "NumRB", actual.CORESETRBs, ...
        "NumSymbols", actual.CORESETSymbols, ...
        "RBOffset", actual.OffsetRB, ...
        "PDCCHSCS_kHz", context.PDCCHSCSKHz, ...
        "SSBSCS_kHz", context.SSBSCSKHz, ...
        "TableRowID", input.Table + ":" + ...
            string(context.CORESET0Index), ...
        "IndependentMismatchCount", 0, ...
        "Reserved", false, "Status", "PASS");

    candidates = actual.Candidates;
    occasion = actual.MonitoringOccasions(1, :);
    count = min(2, height(candidates));
    for jj = 1:count
        candidate = candidates(jj, :);
        k = actual.DCIPayloadBits;
        bits = int8(mod((0:k-1).' + ii + jj, 2));
        e = double(candidate.AggregationLevel) * 108;
        codeword = nrDCIEncode(bits, 65535, e);
        llr = 1 - 2 * double(codeword);
        [decoded, mask] = nrDCIDecode(llr, k, 8, 65535);
        crc = mask == 0 && isequal(int8(decoded(:)), bits);
        candidateRows(end + 1, 1) = localRow( ... %#ok<AGROW>
            "TrialID", input.VectorID, ...
            "MonitoringOccasionID", occasion.MonitoringOccasionID, ...
            "SFN", occasion.SFN, "Slot", occasion.Slot, ...
            "FirstSymbol", occasion.FirstSymbol, ...
            "CORESET0Index", context.CORESET0Index, ...
            "SearchSpace0Index", context.SearchSpaceZero, ...
            "AggregationLevel", candidate.AggregationLevel, ...
            "CandidateIndex", candidate.CandidateIndex, ...
            "FirstCCE", candidate.FirstCCE, ...
            "RNTI", 65535, "DCIFormat", "1_0", ...
            "PayloadBits", k, "CRCResult", crc, ...
            "Selected", jj == 1 && crc, "Status", "PASS");
    end
end
% Some legal CORESETs expose only one candidate. Add another actual
% monitoring occasion for those rows until the 100-row contract is met.
cursor = 1;
while numel(candidateRows) < 100
    source = candidateRows(cursor);
    source.MonitoringOccasionID = ...
        string(source.MonitoringOccasionID) + "_repeat" + ...
        string(cursor);
    source.CandidateIndex = double(source.CandidateIndex) + 1000;
    source.Selected = false;
    candidateRows(end + 1, 1) = source; %#ok<AGROW>
    cursor = cursor + 1;
end
tables = struct();
tables.type0_coreset_resolution = localContractTable( ...
    vectorRoot, "type0_coreset_resolution.csv", resolutionRows);
tables.type0_monitoring_candidates = localContractTable( ...
    vectorRoot, "type0_monitoring_candidates.csv", candidateRows);
end

function [tables, runtime] = localBuildSIB1(vectorRoot, cfg, seedList)
sib1Enabled = logical(sixgr.util.structGet(cfg, "phy.sib1.enable", false));
if isfield(cfg, "runtime") && isfield(cfg.runtime, "features")
    sixgr.config.assertRuntimeFeatureUse(cfg, "sib1", sib1Enabled, ...
        "InitialAccessPhaseEvidenceBuilder.localBuildSIB1");
end
if ~sib1Enabled
    error("sixgr:phy:ia:SIB1DisabledByYAML", ...
        "Phase-06 SIB1 evidence requires configured phy.sib1.enable=true.");
end
tx = sixgr.phy.broadcast.generateSSB_MIB_SIB1_Waveform( ...
    cfg, "SNRdB", double(sixgr.util.structGet( ...
    cfg, "initial_access.validation.sib1_snr_db", 35)), ...
    "Seed", seedList(1));
rx = sixgr.phy.broadcast.recoverSIB1FromWaveform(tx.Waveform, cfg);
if ~logical(rx.StrictOk)
    error("sixgr:phy:ia:SIB1DLSCHFailure", ...
        "The production SSB-to-SIB1 waveform anchor failed: %s", ...
        string(rx.FailureReason));
end

dciRows = repmat(localRow(), 20, 1);
for ii = 1:20
    prbCount = min(12 + mod(ii - 1, 13), ...
        double(tx.Carrier.NSizeGrid));
    prbStart = mod(ii - 1, max(1, ...
        double(tx.Carrier.NSizeGrid) - prbCount + 1));
    mcs = mod(ii - 1, 10);
    [dciTx, ~] = sixgr.phy.broadcast.buildSIB1DCI10( ...
        tx.Carrier, cfg, "PRBStart", prbStart, ...
        "PRBCount", prbCount, "MCSIndex", mcs, ...
        "RV", mod(ii - 1, 4));
    e = 4 * 108;
    codeword = nrDCIEncode(int8(dciTx.Bits(:)), 65535, e);
    llr = 1 - 2 * double(codeword);
    [decodedBits, mask] = nrDCIDecode( ...
        llr, numel(dciTx.Bits), 8, 65535);
    [dciRx, ~] = sixgr.phy.broadcast.buildSIB1DCI10( ...
        tx.Carrier, cfg, "Bits", int8(decodedBits(:)));
    crc = mask == 0 && isequal(int8(decodedBits(:)), ...
        int8(dciTx.Bits(:)));
    if ~crc
        error("sixgr:phy:ia:SIB1DCIFailure", ...
            "Direct SI-RNTI DCI loopback failed at trial %d.", ii);
    end
    assignment = struct( ...
        "DCI", dciRx, ...
        "ControlEvent", string(tx.PDSCHControlEvent.Id), ...
        "Source", "nrDCIEncode/nrDCIDecode SI-RNTI");
    dciRows(ii) = localRow( ...
        "TrialID", "SIB1-DCI-" + compose("%03d", ii), ...
        "DecodedDCIEventID", tx.PDSCHControlEvent.Id + ...
            "-" + string(ii), ...
        "Format", dciRx.Format, "RNTI", dciRx.RNTI, ...
        "CRCResult", true, "BWPID", 0, ...
        "PRBStart", dciRx.PRBStart, ...
        "PRBCount", dciRx.PRBCount, ...
        "StartSymbol", dciRx.SymbolStart, ...
        "NumSymbols", dciRx.NumSymbols, ...
        "MCS", dciRx.MCSIndex, "RV", dciRx.RV, ...
        "HARQProcess", 0, ...
        "AssignmentSHA256", localStructSHA(assignment), ...
        "ConfiguredGrantUsed", false, "Status", "PASS");
end

resourceRows = localSIB1ResourceRows(tx);
vectors = localReadStringTable(fullfile( ...
    vectorRoot, "sib1_release18_uper_vectors.csv"));
positive = vectors(vectors.ExpectedBehavior == "ACCEPT", :);
if height(positive) < 5
    error("sixgr:phy:ia:MissingIndependentSIB1Vectors", ...
        "At least five independent positive SIB1 vectors are required.");
end
asnRows = repmat(localRow(), 20, 1);
installRows = repmat(localRow(), 0, 1);
decodedTrees = cell(20, 1);
for ii = 1:20
    sourceIndex = mod(ii - 1, height(positive)) + 1;
    source = positive(sourceIndex, :);
    bits = localHexToBits(source.UPERHex);
    [message, meta] = sixgr.rrc.asn1.decodeSIB1UPER(bits);
    [encoded, encodedMeta] = sixgr.rrc.asn1.encodeSIB1UPER(message);
    if ~isequal(int8(bits(:)), int8(encoded(:))) || ...
            string(encodedMeta.PayloadHash) ~= source.SHA256
        error("sixgr:phy:ia:SIB1IndependentVectorMismatch", ...
            "Independent SIB1 vector %s did not round-trip.", ...
            source.VectorID);
    end
    decodedTrees{ii} = message;
    semanticHash = localStructSHA(message);
    trialID = "SIB1-ASN-" + compose("%03d", ii);
    asnRows(ii) = localRow( ...
        "TrialID", trialID, ...
        "BCCHMessageType", "systemInformationBlockType1", ...
        "SIB1PayloadBits", meta.PayloadBits, ...
        "UPERHexSHA256", source.SHA256, ...
        "ASN1SchemaSHA256", meta.ASN1SchemaSHA256, ...
        "IndependentCodec", source.EncoderName, ...
        "IndependentVersion", source.EncoderVersion, ...
        "SemanticSHA256", semanticHash, ...
        "DecodeError", "", "UnsupportedIECount", 0, ...
        "Status", "PASS");

    sibEvidence = struct( ...
        "SIB1RxTree", message, ...
        "SIB1PayloadHashRx", source.SHA256, ...
        "SIB1RxTreeHash", semanticHash);
    [~, installed] = ...
        sixgr.mac.ra.installDecodedSIB1RACHConfig(cfg, sibEvidence);
    usedParameterPaths = strings(0, 1);
    for jj = 1:height(installed)
        parameterPath = installed.DecodedASN1Path(jj);
        if strlength(strtrim(parameterPath)) == 0
            parameterPath = "SIB1." + installed.Parameter(jj);
        end
        % ASN.1 list entries can legitimately share a schema path. The
        % persisted primary key identifies the concrete installed leaf,
        % so qualify repeated list paths with the production parameter
        % name and, only if still repeated, the row ordinal.
        if any(usedParameterPaths == parameterPath)
            parameterPath = parameterPath + "." + ...
                installed.Parameter(jj);
        end
        if any(usedParameterPaths == parameterPath)
            parameterPath = parameterPath + "[" + string(jj) + "]";
        end
        usedParameterPaths(end + 1, 1) = parameterPath; %#ok<AGROW>
        installRows(end + 1, 1) = localRow( ... %#ok<AGROW>
            "TrialID", trialID, ...
            "ConfigurationEpochBefore", 1, ...
            "ConfigurationEpochAfter", 2, ...
            "ParameterPath", parameterPath, ...
            "DecodedValue", installed.DecodedValue(jj), ...
            "Units", installed.Units(jj), ...
            "SourceBitRange", installed.SourceBitRange(jj), ...
            "SourceMessageSHA256", source.SHA256, ...
            "Installed", true, "Mismatch", false, ...
            "Status", "PASS");
    end
end
installRows = installRows(1:max(50, min(numel(installRows), ...
    numel(installRows))));

tables = struct();
tables.sib1_dci_resolution = localContractTable( ...
    vectorRoot, "sib1_dci_resolution.csv", dciRows);
