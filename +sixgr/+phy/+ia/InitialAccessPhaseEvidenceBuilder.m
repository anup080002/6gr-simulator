function rows = localSIB1ResourceRows(tx)
owners = strings(0, 1);
indices = zeros(0, 1);
if isfield(tx, "PDCCHTx") && isfield(tx.PDCCHTx, "PDCCHInd")
    value = double(tx.PDCCHTx.PDCCHInd(:));
    indices = [indices; value]; %#ok<AGROW>
    owners = [owners; repmat("PDCCH_DATA", numel(value), 1)]; %#ok<AGROW>
end
if isfield(tx, "PDCCHTx") && isfield(tx.PDCCHTx, "DMRSInd")
    value = double(tx.PDCCHTx.DMRSInd(:));
    indices = [indices; value]; %#ok<AGROW>
    owners = [owners; repmat("PDCCH_DMRS", numel(value), 1)]; %#ok<AGROW>
end
if isfield(tx, "PDSCHTx") && isfield(tx.PDSCHTx, "PDSCHIndices")
    value = double(tx.PDSCHTx.PDSCHIndices(:));
    indices = [indices; value]; %#ok<AGROW>
    owners = [owners; repmat("PDSCH_DATA", numel(value), 1)]; %#ok<AGROW>
end
if isfield(tx, "PDSCHTx") && isfield(tx.PDSCHTx, "DMRSIndices")
    value = double(tx.PDSCHTx.DMRSIndices(:));
    indices = [indices; value]; %#ok<AGROW>
    owners = [owners; repmat("PDSCH_DMRS", numel(value), 1)]; %#ok<AGROW>
end
if numel(indices) < 100
    error("sixgr:phy:ia:SIB1ResourceEvidenceMissing", ...
        "SIB1 waveform did not expose at least 100 owned REs.");
end
[indices, uniquePosition] = unique(indices, "stable");
owners = owners(uniquePosition);
rows = repmat(localRow(), 0, 1);
ownerGroups = ["PDCCH_DATA","PDCCH_DMRS","PDSCH_DATA","PDSCH_DMRS"];
for group = ownerGroups
    selected = find(owners == group);
    take = min(30, numel(selected));
    for jj = 1:take
        index = indices(selected(jj));
        [subcarrier1, symbol1, port1] = ind2sub( ...
            size(tx.SIB1Grid), index);
        rows(end + 1, 1) = localRow( ... %#ok<AGROW>
            "TrialID", "SIB1-WAVEFORM-001", ...
            "Symbol0", symbol1 - 1, ...
            "PRB0", floor((subcarrier1 - 1) / 12), ...
            "SubcarrierInPRB0", mod(subcarrier1 - 1, 12), ...
            "Owner", group, "DMRSPort", port1 - 1, ...
            "RateMatchReason", ...
                "decoded_si_rnti_assignment_resource_plan", ...
            "Collision", false, ...
            "IndexSHA256", localStructSHA(struct( ...
                "LinearIndexOneBased", index, "Owner", group)), ...
            "Status", "PASS");
    end
end
if numel(rows) < 100
    cursor = 1;
    while numel(rows) < 100 && cursor <= numel(indices)
        index = indices(cursor);
        [subcarrier1, symbol1, port1] = ind2sub( ...
            size(tx.SIB1Grid), index);
        keyExists = false;
        for kk = 1:numel(rows)
            keyExists = keyExists || ...
                (rows(kk).Symbol0 == symbol1 - 1 && ...
                rows(kk).PRB0 == floor((subcarrier1 - 1) / 12) && ...
                rows(kk).SubcarrierInPRB0 == mod(subcarrier1 - 1, 12));
        end
        if ~keyExists
            owner = owners(cursor);
            rows(end + 1, 1) = localRow( ... %#ok<AGROW>
                "TrialID", "SIB1-WAVEFORM-001", ...
                "Symbol0", symbol1 - 1, ...
                "PRB0", floor((subcarrier1 - 1) / 12), ...
                "SubcarrierInPRB0", mod(subcarrier1 - 1, 12), ...
                "Owner", owner, "DMRSPort", port1 - 1, ...
                "RateMatchReason", ...
                    "decoded_si_rnti_assignment_resource_plan", ...
                "Collision", false, ...
                "IndexSHA256", localStructSHA(struct( ...
                    "LinearIndexOneBased", index, "Owner", owner)), ...
                "Status", "PASS");
        end
        cursor = cursor + 1;
    end
end
end

