classdef SSBBurstPlan
    %SSBBURSTPLAN Immutable multi-SSB bitmap, timing, beam and power plan.

    methods (Static)
        function plan = fromTiming(timing, varargin)
            if ~isstruct(timing) || ...
                    ~isfield(timing, "Lmax") || ...
                    ~isfield(timing, "CandidateStartSymbolsWithinHalfFrame")
                error("sixgr:phy:ia:InvalidSSBCaseForBand", ...
                    "A resolved canonical SSB timing struct is required.");
            end
            p = inputParser;
            p.FunctionName = "sixgr.phy.ia.SSBBurstPlan.fromTiming";
            addParameter(p, "ActiveBitmap", "", @localBitmapValue);
            addParameter(p, "SelectedSSBIndex", ...
                double(timing.SelectedSSBIndex), @localNonnegativeInteger);
            addParameter(p, "HalfFrameIndex", ...
                double(timing.HalfFrameIndex), @localNonnegativeInteger);
            addParameter(p, "PerSSBPowerDB", [], @localNumericVector);
            addParameter(p, "PrecoderIDs", strings(0, 1), ...
                @localTextVector);
            addParameter(p, "PrecoderMatrices", {}, ...
                @localPrecoderCollection);
            addParameter(p, "StrictBitmapRequired", false, ...
                @localLogicalScalar);
            parse(p, varargin{:});
            opt = p.Results;

            lmax = double(timing.Lmax);
            selectedIndex = double(opt.SelectedSSBIndex);
            if selectedIndex >= lmax
                error("sixgr:phy:ia:SSBIndexOutOfRange", ...
                    "Selected SSB index %d is outside Lmax=%d.", ...
                    selectedIndex, lmax);
            end
            [bitmap, source] = localResolveBitmap( ...
                opt.ActiveBitmap, lmax, selectedIndex, ...
                logical(opt.StrictBitmapRequired));
            powerDB = localExpandNumeric(opt.PerSSBPowerDB, lmax, 0, ...
                "PerSSBPowerDB");
            precoderIDs = localExpandText(opt.PrecoderIDs, lmax, ...
                "identity");
            [precoderMatrices, numTransmitAntennas, precoderHashes] = ...
                localExpandPrecoders(opt.PrecoderMatrices, lmax);
            if all(precoderIDs == "identity") && numTransmitAntennas > 1
                precoderIDs = "configured_precoder_" + string(0:(lmax - 1));
            end

            candidateSymbols = double( ...
                timing.CandidateStartSymbolsWithinHalfFrame(:).');
            if numel(candidateSymbols) ~= lmax
                error("sixgr:phy:ia:InvalidLmax", ...
                    "Canonical timing contains %d candidates for Lmax=%d.", ...
                    numel(candidateSymbols), lmax);
            end
            halfFrame = double(opt.HalfFrameIndex);
            mu = log2(double(timing.SSBSubcarrierSpacingKHz) / 15);
            absoluteSymbols = candidateSymbols + ...
                halfFrame * 5 * (2 ^ mu) * 14;
            indices = (0:(lmax - 1)).';
            rows = table( ...
                indices, candidateSymbols(:), ...
                repmat(halfFrame, lmax, 1), absoluteSymbols(:), ...
                bitmap(:), powerDB(:), precoderIDs(:), ...
                'VariableNames', { ...
                'SSBIndex0', 'CandidateSymbol0', 'HalfFrame', ...
                'AbsoluteSymbol0', 'Active', 'PowerOffset_dB', ...
                'PrecoderID'});

            digestPayload = struct( ...
                "BlockPattern", string(timing.BlockPattern), ...
                "Lmax", lmax, ...
                "PeriodicityMs", double(timing.PeriodicityMs), ...
                "HalfFrameIndex", halfFrame, ...
                "CandidateSymbols0Based", candidateSymbols, ...
                "ActiveBitmap", logical(bitmap), ...
                "PerSSBPowerDB", powerDB, ...
                "PrecoderIDs", precoderIDs, ...
                "PrecoderMatrixSHA256", precoderHashes, ...
                "NumTransmitAntennas", numTransmitAntennas, ...
                "SelectionSource", source);
            plan = struct( ...
                "ContractVersion", "sixgr_ssb_burst_plan/v1", ...
                "BlockPattern", string(timing.BlockPattern), ...
                "Case", string(timing.Case), ...
                "Lmax", lmax, ...
                "PeriodicityMs", double(timing.PeriodicityMs), ...
                "HalfFrameIndex", halfFrame, ...
                "CandidateSymbols0Based", candidateSymbols, ...
                "AbsoluteCandidateSymbols0Based", absoluteSymbols, ...
                "ActiveBitmap", logical(bitmap), ...
                "ActiveSSBIndices0Based", find(bitmap) - 1, ...
                "PerSSBPowerDB", powerDB, ...
                "PrecoderIDs", precoderIDs, ...
                "PrecoderMatrices", {precoderMatrices}, ...
                "PrecoderMatrixSHA256", precoderHashes, ...
                "NumTransmitAntennas", numTransmitAntennas, ...
                "SelectionSource", source, ...
                "Rows", rows, ...
                "Immutable", true, ...
                "PlanSHA256", sixgr.util.sha256Hex( ...
                    jsonencode(digestPayload)));
        end

        function plan = fromConfig(cfg, timing, varargin)
            bitmap = localFirstConfigured(cfg, [ ...
                "phy.ssb.activeBitmap", ...
                "phy.ssb.positionsInBurst", ...
                "reference_signals.ssb_positions_in_burst"]);
            powers = localFirstConfigured(cfg, [ ...
                "phy.ssb.perSSBPower_dB", ...
                "reference_signals.ssb_power_offsets_db"]);
            offset = sixgr.util.structGet(cfg,"phy.ssb.referencePowerOffset_dB",0);
            if isempty(powers), powers = 0; end
            powers = powers + offset;
            precoders = localFirstConfigured(cfg, [ ...
                "phy.ssb.precoderIDs", ...
                "mimo_and_beam_management.ssb_precoder_ids"]);
            precoderMatrices = localFirstConfigured(cfg, [ ...
                "phy.ssb.precoderMatrices", ...
                "mimo_and_beam_management.ssb_precoder_matrices"]);
            strictBitmap = logical(sixgr.util.structGet(cfg, ...
                "initial_access.require_explicit_ssb_bitmap", false));
            plan = sixgr.phy.ia.SSBBurstPlan.fromTiming(timing, ...
                "ActiveBitmap", bitmap, ...
                "PerSSBPowerDB", powers, ...
                "PrecoderIDs", precoders, ...
                "PrecoderMatrices", precoderMatrices, ...
                "StrictBitmapRequired", strictBitmap, ...
                varargin{:});
        end
    end
end

function [bitmap, source] = localResolveBitmap(value, lmax, selected, strict)
if isempty(value) || ...
        ((ischar(value) || isstring(value)) && ...
        strlength(strtrim(string(value))) == 0)
    if strict
        error("sixgr:phy:ia:InvalidSSBBitmap", ...
            "The strict profile requires an explicit Lmax-length bitmap.");
    end
    bitmap = false(1, lmax);
    bitmap(selected + 1) = true;
    source = "compatibility_selected_index";
    return;
end
if islogical(value)
    bitmap = value(:).';
elseif isnumeric(value) && ~isscalar(value)
    bitmap = logical(value(:).');
else
    chars = char(strtrim(string(value)));
    if isempty(chars) || ~all(chars == '0' | chars == '1')
        error("sixgr:phy:ia:InvalidSSBBitmap", ...
            "SSB bitmap must contain only zero and one.");
    end
    bitmap = chars == '1';
end
if numel(bitmap) ~= lmax || ~any(bitmap)
    error("sixgr:phy:ia:InvalidSSBBitmap", ...
        "SSB bitmap must have exactly %d positions and at least one active SSB.", ...
        lmax);
end
source = "configured_ssb_positions_in_burst";
end

function values = localExpandNumeric(raw, count, defaultValue, name)
if isempty(raw)
    values = repmat(double(defaultValue), 1, count);
elseif isscalar(raw)
    values = repmat(double(raw), 1, count);
elseif isnumeric(raw) && isvector(raw) && numel(raw) == count && ...
        all(isfinite(double(raw(:))))
    values = double(raw(:).');
else
    error("sixgr:phy:ia:InvalidSSBBitmap", ...
        "%s must be scalar or contain exactly Lmax finite values.", name);
end
end

function values = localExpandText(raw, count, defaultValue)
if isempty(raw)
    values = repmat(string(defaultValue), 1, count);
else
    values = string(raw(:).');
    if isscalar(values)
        values = repmat(values, 1, count);
    elseif numel(values) ~= count
        error("sixgr:phy:ia:InvalidSSBBitmap", ...
            "PrecoderIDs must be scalar or contain exactly Lmax values.");
    end
end
end

function [matrices, numPorts, hashes] = localExpandPrecoders(raw, count)
if isempty(raw)
    matrices = repmat({1}, 1, count);
elseif iscell(raw)
    matrices = raw(:).';
    if isscalar(matrices)
        matrices = repmat(matrices, 1, count);
    elseif numel(matrices) ~= count
        error("sixgr:phy:ia:InvalidCarrierGrid", ...
            "PrecoderMatrices must contain one matrix or exactly Lmax matrices.");
    end
elseif isnumeric(raw) && ismatrix(raw)
    if size(raw, 1) == 1
        matrices = repmat({raw}, 1, count);
    elseif size(raw, 1) == count
        matrices = cell(1, count);
        for i = 1:count
            matrices{i} = raw(i, :);
        end
    else
        error("sixgr:phy:ia:InvalidCarrierGrid", ...
            "Numeric PrecoderMatrices must have one or Lmax rows.");
    end
else
    error("sixgr:phy:ia:InvalidCarrierGrid", ...
        "PrecoderMatrices must be numeric or a cell array of row vectors.");
end

numPorts = NaN;
hashes = strings(1, count);
for i = 1:count
    matrix = matrices{i};
    if ~(isnumeric(matrix) && ismatrix(matrix) && size(matrix, 1) == 1 && ...
            ~isempty(matrix) && all(isfinite(real(matrix(:)))) && ...
            all(isfinite(imag(matrix(:)))))
        error("sixgr:phy:ia:InvalidCarrierGrid", ...
            "Each SSB precoder must be one finite single-layer row vector.");
    end
    matrixNorm = norm(matrix);
    if abs(matrixNorm - 1) > 1e-9
        error("sixgr:phy:ia:InvalidCarrierGrid", ...
            "Each SSB precoder must have unit Euclidean norm; got %.15g.", ...
            matrixNorm);
    end
    if isnan(numPorts)
        numPorts = size(matrix, 2);
    elseif size(matrix, 2) ~= numPorts
        error("sixgr:phy:ia:InvalidCarrierGrid", ...
            "All SSB precoders must use the same number of antenna ports.");
    end
    matrices{i} = double(matrix);
    hashes(i) = sixgr.util.sha256Hex(jsonencode(struct( ...
        "Size", size(matrix), ...
        "Real", real(double(matrix)), ...
        "Imag", imag(double(matrix)))));
end
numPorts = double(numPorts);
end

function value = localFirstConfigured(cfg, paths)
value = [];
for path = paths
    candidate = sixgr.util.structGet(cfg, path, []);
    if ~isempty(candidate)
        value = candidate;
        return;
    end
end
end

function tf = localBitmapValue(value)
tf = isempty(value) || ischar(value) || isstring(value) || ...
    isnumeric(value) || islogical(value);
end

function tf = localNumericVector(value)
tf = isempty(value) || (isnumeric(value) && isvector(value));
end

function tf = localTextVector(value)
tf = isempty(value) || ischar(value) || isstring(value) || iscellstr(value);
end

function tf = localPrecoderCollection(value)
tf = isempty(value) || isnumeric(value) || iscell(value);
end

function tf = localNonnegativeInteger(value)
tf = isnumeric(value) && isscalar(value) && isfinite(value) && ...
    value >= 0 && value == fix(value);
end

function tf = localLogicalScalar(value)
tf = (islogical(value) || isnumeric(value)) && isscalar(value);
end
