classdef InitialAccessSpecificationProfile
    %INITIALACCESSSPECIFICATIONPROFILE Release-pinned strict IA profile.
    %
    % The bounded production profile deliberately exposes only the FR1
    % four-step contention-based procedure that is implemented through
    % RRCSetupComplete.  Unsupported access families are capability errors,
    % never aliases or fallbacks.

    methods (Static)
        function profile = resolve(profileId)
            if nargin < 1 || strlength(strtrim(string(profileId))) == 0
                profileId = "fr1_four_step_ra_rrc_connection_strict_r18";
            end
            requested = lower(strtrim(string(profileId)));
            aliases = [ ...
                "fr1_four_step_ra_rrc_connection_strict_r18", ...
                "fr1_four_step_rrc_connection_strict"];
            if ~isscalar(requested) || ~any(requested == aliases)
                error("sixgr:phy:ia:UnsupportedProfile", ...
                    "Initial-access profile '%s' is not executable.", ...
                    string(profileId));
            end

            specifications = struct( ...
                "TS38211", "3GPP TS 38.211 V18.8.0", ...
                "TS38212", "3GPP TS 38.212 V18.8.0", ...
                "TS38213", "3GPP TS 38.213 V18.8.0", ...
                "TS38214", "3GPP TS 38.214 V18.8.0", ...
                "TS38321", "3GPP TS 38.321 V18.8.0", ...
                "TS38331", "3GPP TS 38.331 V18.9.0");

            profile = struct( ...
                "ProfileID", "fr1_four_step_ra_rrc_connection_strict_r18", ...
                "RequestedProfileID", requested, ...
                "ContractVersion", "sixgr_initial_access_profile/v1", ...
                "Release", "Release 18", ...
                "Specifications", specifications, ...
                "FrequencyRange", "FR1", ...
                "SupportedSSBCases", ["A", "B", "C"], ...
                "SupportedLmax", [4, 8], ...
                "SupportedSSBPeriodicityMs", [5, 10, 20, 40, 80, 160], ...
                "RandomAccessProcedure", "four_step_contention_based", ...
                "RRCCompletionCriterion", "RRCSetupComplete_accepted_by_gNB", ...
                "Strict", true, ...
                "ResearchClassification", "benchmark_compliance", ...
                "ProxyAllowed", false, ...
                "FallbackAllowed", false, ...
                "CapabilityEpoch", uint64(1));
        end

        function tableOut = specificationTable(profileId)
            profile = sixgr.phy.ia.InitialAccessSpecificationProfile.resolve( ...
                profileId);
            names = string(fieldnames(profile.Specifications));
            values = strings(numel(names), 1);
            for i = 1:numel(names)
                values(i) = string(profile.Specifications.(names(i)));
            end
            tableOut = table(names, values, ...
                'VariableNames', {'SpecificationKey', 'PinnedVersion'});
        end
    end
end
