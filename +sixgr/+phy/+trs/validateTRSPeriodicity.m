function evidence = validateTRSPeriodicity(cfg)
%VALIDATETRSPERIODICITY Validate the actual recurring trs-Info calendar.
% TS 38.214 V18.8.0, 5.1.6.1.1: Xp*2^mu slots, Xp=10/20/40/80 ms;
% 10 ms is not supported when the resource bandwidth exceeds 52 RBs.
% Explicit within-frame resource sets also recur: each complete set repeats
% every 10 ms. Multiple distinct sets do not change each set's periodicity.
% This does not certify the other TRS/RRC, UE capability or RF requirements.
arguments
    cfg (1,1) struct
end
id = 'sixgr:phy:trs:TRSCadenceNativeMismatch';
assert(isfield(cfg,'ToolboxCarrier') && isa(cfg.ToolboxCarrier,'nrCarrierConfig') && ...
    isscalar(cfg.ToolboxCarrier) && isfield(cfg,'ToolboxResources') && ...
    iscell(cfg.ToolboxResources) && ~isempty(cfg.ToolboxResources),id, ...
    'TRS periodicity must be bound to the actual native carrier and resources.');
carrier = cfg.ToolboxCarrier;
scs = double(carrier.SubcarrierSpacing);
ratio = scs/15;
assert(isfinite(ratio) && ratio>=1 && log2(ratio)==fix(log2(ratio)) && ...
    localEqualScalar(cfg,'SubcarrierSpacingKHz',scs) && ...
    localEqualScalar(cfg,'NSizeGrid',double(carrier.NSizeGrid)) && ...
    localEqualScalar(cfg,'NStartGrid',double(carrier.NStartGrid)),id, ...
    'The declared TRS carrier must match the native carrier numerology and grid.');
numRB = localInteger(cfg,'NumRB',1,id);
rbOffset = localInteger(cfg,'RBOffset',0,id);
assert(rbOffset+numRB<=double(carrier.NSizeGrid),id, ...
    'TRS bandwidth must fit the native carrier without clipping.');
for k = 1:numel(cfg.ToolboxResources)
    resource = cfg.ToolboxResources{k};
    assert(isa(resource,'nrCSIRSConfig') && isscalar(resource) && ...
        isequal(double(resource.NumRB),numRB) && ...
        isequal(double(resource.RBOffset),rbOffset),id, ...
        'Every native TRS resource must retain the original bandwidth and offset.');
end
authority = sixgr.util.structGet(cfg,'SlotAuthority',"");
assert((ischar(authority) || isstring(authority)) && isscalar(string(authority)), ...
    'sixgr:phy:trs:InvalidRecurringSlotAuthority','TRS requires an explicit recurring calendar authority.');
authority = string(authority);
configuredSlots = localSlots(cfg,'ConfiguredSlotNumbers');
selectedSlots = localSlots(cfg,'SlotNumbers');
burst = localInteger(cfg,'BurstLengthSlots',1,'sixgr:phy:trs:InvalidRecurringSlotAuthority');
assert(burst==2,'sixgr:phy:trs:InvalidRecurringSlotAuthority', ...
    'The implemented tracking receiver supports complete two-slot sets only.');
switch authority
    case "periodic_offset"
        period = localInteger(cfg,'PeriodSlots',1,'sixgr:phy:trs:InvalidPeriodicCadence');
        offset = localInteger(cfg,'PeriodOffset',0,'sixgr:phy:trs:InvalidPeriodicCadence');
        assert(offset<period,'sixgr:phy:trs:InvalidPeriodicCadence', ...
            'TRS period offset must be less than the original period.');
        periodMs = period/ratio;
        assert(ismember(periodMs,[10 20 40 80]), ...
            'sixgr:phy:trs:InvalidPeriodicCadence', ...
            'TRS period %g slots at %g kHz is %g ms; expected 10, 20, 40 or 80 ms.', ...
            period,scs,periodMs);
        assert(isequal(configuredSlots,offset+(0:burst-1)) && ...
            numel(selectedSlots)==burst && selectedSlots(1)>=offset && ...
            mod(selectedSlots(1)-offset,period)==0 && all(diff(selectedSlots)==1), ...
            'sixgr:phy:trs:InvalidRecurringSlotAuthority', ...
            'Selected and configured TRS slots must match the original periodic resource set.');
        setCount = 1;
    case "explicit_slot_numbers"
        % These are the original frame-relative slots, not a later runtime
        % window's absolute slots (which can be in any carrier frame).
        slots = configuredSlots;
        assert(all(slots<double(carrier.SlotsPerFrame)) && mod(numel(slots),burst)==0, ...
            'sixgr:phy:trs:InvalidRecurringSlotAuthority', ...
            'Recurring TRS slots must retain complete ordered two-slot sets within the native frame.');
        assert(all(diff(reshape(slots,2,[]),1,1)==1,'all'), ...
            'sixgr:phy:trs:InvalidRecurringSlotAuthority', ...
            'Each implemented recurring TRS resource set requires two consecutive slots.');
        period = double(carrier.SlotsPerFrame);
        periodMs = period/ratio;
        assert(periodMs==10,id,'Native frame duration must be 10 ms.');
        setCount = numel(slots)/2;
    otherwise
        error('sixgr:phy:trs:InvalidRecurringSlotAuthority', ...
            'Unsupported TRS recurring calendar authority %s.',authority);
end
window=sixgr.util.structGet(cfg,'RuntimeObservationWindow',struct());
assert(isstruct(window) && isscalar(window), ...
    'sixgr:phy:trs:InvalidRecurringSlotAuthority','TRS runtime observation must be a scalar original window.');
if ~isempty(fieldnames(window))
    assert(string(sixgr.util.structGet(window,'Authority',""))==authority && ...
        isequal(localSlots(window,'AbsoluteSlotNumbers'),selectedSlots), ...
        'sixgr:phy:trs:InvalidRecurringSlotAuthority', ...
        'Retained TRS slots must match the original selected runtime observation.');
    if authority=="explicit_slot_numbers"
        assert(isequal(localSlots(window,'ConfiguredSlotNumbers'),configuredSlots) && ...
            numel(selectedSlots)==burst, ...
            'sixgr:phy:trs:InvalidRecurringSlotAuthority','Original frame resources changed after selection.');
        setIndex=localInteger(window,'ResourceSetIndex0Based',0, ...
            'sixgr:phy:trs:InvalidRecurringSlotAuthority');
        assert(setIndex<setCount && isequal(mod(selectedSlots,double(carrier.SlotsPerFrame)), ...
            configuredSlots(setIndex*burst+(1:burst))), ...
            'sixgr:phy:trs:InvalidRecurringSlotAuthority', ...
            'Runtime TRS resource-set identity must select the original frame-relative slots.');
    end
else
    assert(isequal(selectedSlots,configuredSlots), ...
        'sixgr:phy:trs:InvalidRecurringSlotAuthority', ...
        'Without an original runtime window, selected TRS slots must equal the configured slots.');
end
assert(double(carrier.NSlot)==mod(selectedSlots(1),double(carrier.SlotsPerFrame)) && ...
    double(carrier.NFrame)==mod(floor(selectedSlots(1)/double(carrier.SlotsPerFrame)),1024), ...
    id,'Native TRS carrier clock must bind the selected original resource set.');
assert(periodMs~=10 || numRB<=52, ...
    'sixgr:phy:trs:TRSPeriodicityBandwidth', ...
    ['TS 38.214 V18.8.0 5.1.6.1.1 does not support a 10-ms periodic ' ...
     'trs-Info resource wider than 52 RBs (actual bandwidth %g RBs).'],numRB);
evidence = struct('ContractVersion',"sixgr.phy.trs.Periodicity/v1", ...
    'RequirementClass',"NR_NORMATIVE", ...
    'Specification',"TS38.214-V18.8.0-5.1.6.1.1", ...
    'Scope',"recurring_TRS_period_and_bandwidth_only", ...
    'SlotAuthority',authority,'SubcarrierSpacingKHz',scs,'NumRB',numRB, ...
    'PeriodSlots',period,'PeriodMilliseconds',periodMs, ...
    'ResourceSetsPerCalendar',setCount,'Valid',true);
end

function slots=localSlots(cfg,name)
slots=sixgr.util.structGet(cfg,name,[]);
assert(isnumeric(slots) && isreal(slots) && isvector(slots) && ~isempty(slots) && ...
    all(isfinite(slots)) && all(slots>=0 & slots<=flintmax & slots==fix(slots)) && ...
    all(diff(slots(:))>0), 'sixgr:phy:trs:InvalidRecurringSlotAuthority', ...
    'TRS %s must contain the original ordered unique nonnegative slot indices.',name);
slots=reshape(double(slots),1,[]);
end

function value = localInteger(cfg,name,minimum,id)
value = sixgr.util.structGet(cfg,name,NaN);
assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && value>=minimum && value==fix(value) && value<=flintmax, ...
    id,'TRS %s must be an exact finite integer >=%g.',name,minimum);
value = double(value);
end

function tf = localEqualScalar(cfg,name,expected)
value = sixgr.util.structGet(cfg,name,[]);
tf = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && double(value)==expected;
end
