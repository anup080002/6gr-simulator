function [timingOffset, info] = timingEstimate(rxWaveform, arg2, arg3, arg4, varargin)
%timingEstimate Estimate SSB timing offset using NR timing estimator.
%
%   [timingOffset, info] = sixgr.phy.sync.timingEstimate(rxWaveform, NID2,
%   blockPattern, sampleRateHz)
%
%   Backward-compatible calling form (older internal call sites):
%   timingEstimate(rxWaveform, blockPattern, sampleRateHz, NID2)
%
%   Inputs
%     rxWaveform   : Nsamp-by-Nr complex samples
%     NID2         : physical-layer cell ID group (0..2)
%     blockPattern : 'Case A' through 'Case G'
%     sampleRateHz : sampling rate in Hz
%
%   Name-value options
%     'UseAntenna' : scalar antenna index for timing (default: 1)
%     'SSBTiming'  : canonical SSBTimingResolver result. New standard-path
%                    callers must provide this object.
%
%   Outputs
%     timingOffset : sample offset returned by nrTimingEstimate
%     info         : struct with debug fields

    % Parse positional args in a robust way.
    % Expected (preferred): (rxWaveform, NID2, blockPattern, sampleRateHz)
    % Alternate (legacy):  (rxWaveform, blockPattern, sampleRateHz, NID2)
    NID2 = [];
    blockPattern = 'Case B';
    sampleRateHz = [];

    if nargin < 4
        error('sixgr:phy:sync:timingEstimate:BadInputs', 'Expected at least 4 inputs.');
    end

    if isnumeric(arg2) && isscalar(arg2)
        NID2 = double(arg2);
        blockPattern = arg3;
        sampleRateHz = double(arg4);
    elseif ischar(arg2) || isstring(arg2)
        blockPattern = arg2;
        sampleRateHz = double(arg3);
        NID2 = double(arg4);
    else
        error('sixgr:phy:sync:timingEstimate:BadInputs', 'Unsupported input ordering/types.');
    end

    % Name-value parsing
    p = inputParser;
    p.addParameter('UseAntenna', 1, @(x) isnumeric(x) && isscalar(x) && x >= 1);
    p.addParameter('SSBTiming', struct(), @localOptionalTiming);
    p.parse(varargin{:});
    opt = p.Results;

    if isvector(rxWaveform)
        rxWaveform = rxWaveform(:);
    end

    blockPattern = char(string(blockPattern));
    ssbTiming = localResolveTiming(blockPattern, opt.SSBTiming);

    if isempty(sampleRateHz) || ~isfinite(sampleRateHz) || sampleRateHz <= 0
        error('sixgr:phy:sync:timingEstimate:BadSampleRate', 'sampleRateHz must be a positive scalar.');
    end

    if isempty(NID2) || ~isscalar(NID2) || NID2 < 0 || NID2 > 2
        error('sixgr:phy:sync:timingEstimate:BadNID2', 'NID2 must be 0, 1, or 2.');
    end

    Nr = size(rxWaveform, 2);
    ant = min(max(1, round(opt.UseAntenna)), Nr);
    % Simulator captures generated by SSB_Tx start on an NR frame
    % boundary.  Initial SS/PBCH candidates occupy the first 5 ms
    % half-frame.  Searching the later composed SIB1/PDSCH timeline allows
    % high-energy data symbols to create a false late PSS timing peak.
    timingSearchSamples = min(size(rxWaveform, 1), ...
        max(1, ceil(5e-3 * double(sampleRateHz))));
    timingWaveform = rxWaveform(1:timingSearchSamples, ant);

    % Use a 4-symbol SSB-shaped reference grid. PSS occupies symbol 2 of the
    % SS/PBCH block per TS 38.211 7.4.3.1; using a 2-symbol shortcut biases
    % timing against the actual SSB OFDM symbol layout.
    nrbSSB = 20;
    scsSSB_kHz = double(ssbTiming.SSBSubcarrierSpacingKHz);
    initialNSlot = 0;

    refGrid = complex(zeros(nrbSSB*12, 4));
    pssSym = nrPSS(NID2);
    try
        pssSub = nrPSSIndices('IndexStyle', 'subscript', 'IndexBase', '1based');
        if size(pssSub, 2) >= 2
            refGrid(sub2ind(size(refGrid), pssSub(:,1), pssSub(:,2))) = pssSym;
        else
            refGrid(double(pssSub(:)), 2) = pssSym;
        end
    catch
        pssInd = nrPSSIndices();
        try
            [row_pss, col_pss] = ind2sub(size(refGrid), pssInd);
            refGrid(sub2ind(size(refGrid), row_pss(:), col_pss(:))) = pssSym;
        catch
            refGrid(double(pssInd(:)), 2) = pssSym;
        end
    end

    % Provide SampleRate to match the input waveform.
    % Prefer the refGrid syntax; fall back to refInd/refSym if required.
    try
        timingOffset = nrTimingEstimate(timingWaveform, nrbSSB, scsSSB_kHz, initialNSlot, refGrid, ...
            'SampleRate', sampleRateHz);
    catch
        pssInd = nrPSSIndices();
        timingOffset = nrTimingEstimate(timingWaveform, nrbSSB, scsSSB_kHz, initialNSlot, pssInd, pssSym, ...
            'SampleRate', sampleRateHz);
    end

    timingOffset = double(timingOffset);
    if ~isfinite(timingOffset) || timingOffset < 0 || ...
            timingOffset >= timingSearchSamples
        % Console/diary streams are optional diagnostics.  A closed WebGUI
        % batch stream must not turn an otherwise recoverable timing
        % hypothesis into a PHY exception.
        sixgr.util.safeFprintf(2, ...
            '[sixgr:sync:BadTimingEstimate] SSB timing estimate %.3f is out of the %d-sample initial half-frame search window. Clamped to 0.\n', ...
            double(timingOffset), timingSearchSamples);
        timingOffset = 0;
    end

    info = struct();
    info.NID2 = double(NID2);
    info.BlockPattern = blockPattern;
    info.SubcarrierSpacing_kHz = scsSSB_kHz;
    info.NRBSSB = nrbSSB;
    info.InitialNSlot = initialNSlot;
    info.SampleRate_Hz = double(sampleRateHz);
    info.SearchSamples = double(timingSearchSamples);
    info.SearchDuration_ms = 1e3 * double(timingSearchSamples) / ...
        double(sampleRateHz);
    info.UseAntenna = ant;
    info.RawTimingEstimate_samples = double(timingOffset);
    info.TimingEstimateStatus = "available_raw_estimate";
    info.SSBTiming = ssbTiming;
end

function timing = localResolveTiming(blockPattern, supplied)
    if isstruct(supplied) && isscalar(supplied) && ...
            ~isempty(fieldnames(supplied))
        timing = localValidateTiming(supplied, blockPattern);
        return;
    end

    % Compatibility-only positional signature. Case validation and SCS
    % selection remain owned by the canonical SSB timing resolver.
    caseLetter = localCaseLetter(blockPattern);
    if any(caseLetter == ["A", "B", "C"])
        range = "FR1";
        lmax = 8;
    elseif any(caseLetter == ["D", "E"])
        range = "FR2-1";
        lmax = NaN;
    else
        range = "FR2-2";
        lmax = NaN;
    end
    timing = sixgr.phy.frame.SSBTimingResolver.resolve( ...
        "Case", caseLetter, ...
        "FrequencyRange", range, ...
        "Lmax", lmax);
end

function timing = localValidateTiming(timing, blockPattern)
    required = ["BlockPattern", "SSBSubcarrierSpacingKHz", ...
        "CandidateIndices", "CandidateStartSymbolsWithinHalfFrame", ...
        "Lmax", "ResolvedValid"];
    missing = required(~isfield(timing, cellstr(required)));
    if ~isempty(missing)
        error("sixgr:phy:sync:InvalidSSBTiming", ...
            "SSBTiming is missing canonical fields: %s.", ...
            strjoin(missing, ", "));
    end
    if ~(isscalar(timing.ResolvedValid) && logical(timing.ResolvedValid))
        error("sixgr:phy:sync:InvalidSSBTiming", ...
            "SSBTiming must be a successfully resolved canonical object.");
    end
    expected = localCaseLetter(blockPattern);
    actual = localCaseLetter(timing.BlockPattern);
    if actual ~= expected
        error("sixgr:phy:sync:SSBTimingCaseMismatch", ...
            "BlockPattern %s conflicts with supplied SSBTiming %s.", ...
            string(blockPattern), string(timing.BlockPattern));
    end
end

function letter = localCaseLetter(raw)
    letter = upper(strtrim(string(raw)));
    if ~isscalar(letter) || strlength(letter) == 0
        error("sixgr:phy:frame:MissingSSBCase", ...
            "An explicit SSB case A through G is required.");
    end
    letter = strtrim(erase(letter, "CASE"));
    if ~any(letter == ["A", "B", "C", "D", "E", "F", "G"])
        error("sixgr:phy:frame:UnsupportedSSBCase", ...
            "Unsupported SSB case '%s'; expected Case A through Case G.", ...
            string(raw));
    end
end

function tf = localOptionalTiming(value)
    tf = isstruct(value) && isscalar(value);
end
