function identity = receivedSSBOccasionIdentity(sync, pbch)
%RECEIVEDSSBOCCASIONIDENTITY Keep received window separate from BCH hypothesis.
% The PSS search selects an actual canonical timing window before PBCH
% decoding. Failed BCH bits/DM-RS hypotheses cannot relabel that window.
timing = sync.SSBTiming;
starts = double(timing.CandidateStartSymbolsWithinHalfFrame(:));
indices = double(timing.CandidateIndices(:));
selected = double(sync.SelectedCandidateStartSymbol);
assert(isscalar(selected) && isfinite(selected) && selected >= 0 && ...
    selected == fix(selected) && numel(starts) == numel(indices) && ...
    all(isfinite(starts)) && all(isfinite(indices)) && ...
    all(indices >= 0 & indices == fix(indices)) && ...
    numel(unique(indices)) == numel(indices), ...
    'sixgr:phy:sync:InvalidReceivedSSBOccasion', ...
    'Received SSB identity requires a valid canonical timing map and PSS-selected window.');
hit = starts == selected;
assert(nnz(hit) == 1, 'sixgr:phy:sync:InvalidReceivedSSBOccasion', ...
    'The received PSS window must resolve to exactly one SSB occasion.');
observed = indices(hit);
hypothesis = double(sixgr.util.structGet(pbch, 'SSBIndex', NaN));
assert(isscalar(hypothesis), 'sixgr:phy:sync:InvalidReceivedSSBOccasion', ...
    'The PBCH receiver must retain one hypothesis, not a vector of beam IDs.');
crcPass = logical(pbch.Ok) && double(pbch.ErrFlag) == 0;
identity = struct('ObservedSSBOccasionIndex', observed, ...
    'PBCHHypothesisSSBIndex', hypothesis, ...
    'SSBIdentityVerified', crcPass && isfinite(hypothesis) && hypothesis == observed, ...
    'SSBIndexSource', "received_pss_candidate_window");
end
