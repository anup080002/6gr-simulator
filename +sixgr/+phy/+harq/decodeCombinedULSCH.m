function [ok,meanIter,tbBits,diagnostics]=decodeCombinedULSCH(layout,recLLR,cfg)
% Decode receiver-owned rate-recovered UL soft bits. No TX metadata input.
% TS 38.212 6.2.1/6.2.3: TB CRC and LDPC segmentation remain those of the
% retained TB; a later RV does not establish a new transport-block size.
% Transport acceptance follows the TB CRC and actual length, matching the
% canonical nrULSCHDecoder TB verdict. Optional diagnostics retain CB CRC
% results separately; a CB CRC failure is not an additional TB rejection.
fields={'Direction','TransportBlockSize','TBCRCType','TBCRCLength', ...
    'BaseGraph','MotherCodeLength','NumCodeBlocks','LiftingSize','B'};
assert(isstruct(layout) && isscalar(layout) && all(isfield(layout,fields)) && ...
    string(layout.Direction)=="UL",'sixgr:phy:harq:ULReceiverCodingLayoutRequired', ...
    'Combined UL decoding requires the receiver coding layout, not a transmitter object.');
A=double(layout.TransportBlockSize); bgn=double(layout.BaseGraph);
N=double(layout.MotherCodeLength); C=double(layout.NumCodeBlocks); z=double(layout.LiftingSize);
validateattributes(A,{'double'},{'scalar','integer','positive','finite'});
crcType="16"; crcLength=16;
if A>3824, crcType="24A"; crcLength=24; end
assert(ismember(bgn,[1 2]) && z>0 && z==fix(z) && ...
    N==(66*(bgn==1)+50*(bgn==2))*z && C>=1 && C==fix(C) && ...
    string(layout.TBCRCType)==crcType && double(layout.TBCRCLength)==crcLength && ...
    double(layout.B)==A+crcLength,'sixgr:phy:harq:ULReceiverCodingLayoutMismatch', ...
    'Receiver LDPC dimensions and TB CRC must agree with the retained UL transport block.');
assert(isnumeric(recLLR) && isreal(recLLR) && isequal(size(recLLR),[N C]) && ...
    ~any(isnan(recLLR(:))),'sixgr:phy:harq:ULCombinedLLRShapeMismatch', ...
    'Rate-recovered UL soft bits must match the receiver mother-code rows and code blocks.');
policy=sixgr.phy.phycode.resolveLDPCPolicy(cfg);
maxIter=sixgr.phy.phycode.resolveLDPCMaxIterations(cfg,'Direction','UL');
K=(22*(bgn==1)+10*(bgn==2))*z;
[decoded,iterations,parity,policyReceipt]=sixgr.phy.phycode.decodeLDPCConfigured( ...
    double(recLLR),bgn,maxIter,policy, ...
    logical(sixgr.util.structGet(policy,'useMexBatchDecode',false)));
assert(isequal(size(decoded),[K C]),'sixgr:phy:harq:ULDecodedCodeBlockShapeMismatch', ...
    'LDPC output must match receiver code-block dimensions.');
[withCRC,cbError]=sixgr.phy.tb.desegmentLDPC(decoded,bgn,A+crcLength);
[tbBits,tbOK,tbError]=sixgr.phy.tb.checkCRC(withCRC,char(crcType));
tbBits=int8(tbBits(:));
lengthMatch=numel(tbBits)==A;
ok=logical(tbOK && lengthMatch);
meanIter=mean(iterations,'omitnan');
if nargout>3
    diagnostics=struct('ContractVersion',"CombinedSCHDecodeDiagnostics/v1", ...
        'Direction',"UL",'TransportBlockSize',A, ...
        'LDPCPolicyReceipt',policyReceipt,'FinalParityChecks',parity, ...
        'LDPCParityEvidence',sixgr.phy.phycode.summarizeLDPCParity({parity},"harq_combined_decode"), ...
        'DecodedTransportBlockLength',numel(tbBits), ...
        'TransportBlockLengthMatch',logical(lengthMatch), ...
        'TransportBlockCRCPass',logical(tbOK),'TransportBlockCRCError',logical(tbError), ...
        'CodeBlockCRCError',cbError,'CodeBlockCRCPass',~logical(cbError), ...
        'CRCPass',ok,'AcceptanceBasis',"transport_block_crc_and_length");
end
end
