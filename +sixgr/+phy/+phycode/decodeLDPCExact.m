function [decoded,iterations,finalParityChecks,receipt]=decodeLDPCExact(llr,bgn,maxIterations,varargin)
%DECODELDPCEXACT Exact native decoder policy and complete parity evidence.
% Receiver implementation policy, not a 3GPP-mandated decoding algorithm.
% This entry calls nrLDPCDecode once; it neither retries a different policy
% nor substitutes the old one-bit batch ABI. The default algorithm preserves
% the native primitive's BP behavior. Configured NMS callers must supply NMS.
% All supplied LLRs are receiver/rate-recovery operands; no TX reference is
% accepted. The caller retains responsibility for CB/TB CRC and HARQ identity.
%
% Name/value options match the native public policy: Algorithm, ScalingFactor,
% Offset, Termination. Full parity is returned as checks-by-code-block, not
% its first row, a flattened vector or an iteration trace.
ip=inputParser; ip.FunctionName=mfilename; ip.PartialMatching=false;
ip.addParameter('Algorithm','Belief propagation',@localTextScalar);
ip.addParameter('ScalingFactor',0.75);
ip.addParameter('Offset',0.5);
ip.addParameter('Termination','early',@localTextScalar);
ip.parse(varargin{:}); opt=ip.Results;
algorithms=["Belief propagation","Layered belief propagation", ...
    "Normalized min-sum","Offset min-sum"];
algorithmIndex=find(strcmpi(string(opt.Algorithm),algorithms),1);
assert(~isempty(algorithmIndex),'sixgr:phy:LDPCExactPolicy', ...
    'Algorithm must name a supported complete native LDPC algorithm.');
algorithm=algorithms(algorithmIndex);
termination=lower(string(opt.Termination));
assert(ismember(termination,["early","max"]),'sixgr:phy:LDPCExactPolicy', ...
    'Termination must be early or max.');
validateattributes(opt.ScalingFactor,{'numeric'}, ...
    {'real','scalar','finite','>',0,'<=',1},mfilename,'ScalingFactor');
validateattributes(opt.Offset,{'numeric'}, ...
    {'real','scalar','finite','nonnegative'},mfilename,'Offset');
validateattributes(bgn,{'numeric'},{'real','scalar','integer','finite'},mfilename,'bgn');
assert(ismember(bgn,[1 2]),'sixgr:phy:LDPCExactBGN','Base graph must be 1 or 2.');
validateattributes(maxIterations,{'numeric'}, ...
    {'real','scalar','integer','finite','positive'},mfilename,'maxIterations');
assert((isnumeric(llr)||islogical(llr)) && isreal(llr) && ...
    ismatrix(llr) && ~isempty(llr) && ~issparse(llr) && ~any(isnan(llr),'all'), ...
    'sixgr:phy:LDPCExactLLR','Require a real nonempty rate-recovered LLR matrix without NaN.');
% Inf remains valid for decoder/filler LLRs. This wrapper does not invent a
% filler layout or replace infinite receiver inputs with finite confidence.
if isvector(llr), llr=llr(:); end
if ~isa(llr,'single') && ~isa(llr,'double'), llr=double(llr); end
assert(exist('nrLDPCDecode','file')==2,'sixgr:Missing5GToolbox', ...
    'nrLDPCDecode is required for exact native LDPC execution.');
args={'Algorithm',char(algorithm),'Termination',char(termination)};
appliedScaling=NaN; appliedOffset=NaN;
if algorithm=="Normalized min-sum"
    appliedScaling=double(opt.ScalingFactor);
    args=[args,{'ScalingFactor',appliedScaling}];
elseif algorithm=="Offset min-sum"
    appliedOffset=double(opt.Offset);
    args=[args,{'Offset',appliedOffset}];
end
[decoded,iterations,finalParityChecks]=nrLDPCDecode( ...
    llr,double(bgn),double(maxIterations),args{:});
blocks=size(llr,2);
assert(ismatrix(decoded)&&size(decoded,2)==blocks && ...
    numel(iterations)==blocks && all(isfinite(iterations),'all') && ...
    all(iterations>=1 & iterations<=maxIterations,'all') && ...
    ismatrix(finalParityChecks)&&size(finalParityChecks,2)==blocks && ...
    size(finalParityChecks,1)>0 && all(ismember(finalParityChecks,[0 1]),'all'), ...
    'sixgr:phy:LDPCExactOutput','Native output must retain every code block and its final parity checks.');
receipt=struct('ContractVersion',"sixgr.phy.LDPCExactPolicy/v1", ...
    'PolicyAuthority',"receiver_implementation_policy", ...
    'DefaultedOptions',string(ip.UsingDefaults), ...
    'DefaultAuthority',"documented_native_nrLDPCDecode_API_defaults_not_scenario_resolution", ...
    'RequestedAlgorithm',string(opt.Algorithm),'AppliedAlgorithm',algorithm, ...
    'ConfiguredScalingFactor',double(opt.ScalingFactor), ...
    'AppliedScalingFactor',appliedScaling,'ScalingFactorApplicable',algorithm=="Normalized min-sum", ...
    'ConfiguredOffset',double(opt.Offset),'AppliedOffset',appliedOffset, ...
    'OffsetApplicable',algorithm=="Offset min-sum", ...
    'RequestedTermination',string(opt.Termination),'AppliedTermination',termination, ...
    'MaximumIterations',double(maxIterations),'ActualIterationsPerCodeBlock',double(iterations(:).'), ...
    'BaseGraph',double(bgn),'CodeBlockCount',blocks, ...
    'InputLLRClass',string(class(llr)),'DecodedShape',double(size(decoded)), ...
    'FinalParityCheckShape',double(size(finalParityChecks)), ...
    'FinalParityScope',"complete_native_final_parity_matrix_checks_by_codeblock", ...
    'UnsatisfiedParityChecksPerCodeBlock',sum(double(finalParityChecks)~=0,1), ...
    'AllParityChecksSatisfiedPerCodeBlock',all(finalParityChecks==0,1), ...
    'DecoderEngine',"nrLDPCDecode",'DecoderFunctionPath',string(which('nrLDPCDecode')), ...
    'MATLABRelease',string(version('-release')),'MEXApplied',false, ...
    'AlgorithmSubstitutionApplied',false,'RetryApplied',false, ...
    'TransportBlockAcceptanceDetermined',false);
end

function tf=localTextScalar(x)
tf=(ischar(x)&&isrow(x)&&~isempty(x)) || ...
    (isstring(x)&&isscalar(x)&&~ismissing(x)&&strlength(x)>0);
end
