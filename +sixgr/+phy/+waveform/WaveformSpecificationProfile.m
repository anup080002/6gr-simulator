classdef WaveformSpecificationProfile
    %WAVEFORMSPECIFICATIONPROFILE Pinned claim and execution boundary.

    properties (Constant)
        TS38211 = "3GPP TS 38.211 V19.3.0 (Release 19, 2026-04)"
        TS38214 = "3GPP TS 38.214 V19.3.0 (Release 19)"
        TS38331 = "3GPP TS 38.331 V19.3.0 (Release 19)"
    end

    methods (Static)
        function profile = resolve(profileID)
            id = lower(strtrim(string(profileID)));
            known = ["nr_rel19_cp_ofdm_strict", ...
                "nr_rel19_ul_dfts_ofdm_strict", ...
                "nr_rel19_multinumerology_strict", ...
                "rel20_6g_waveform_study", ...
                "waveform_research_candidate", ...
                "unsupported_extension"];
            if ~isscalar(id) || ~ismember(id,known)
                error("WAVEFORM:UnsupportedProfile", ...
                    "Unknown waveform profile '%s'.",string(profileID));
            end
            normative = ismember(id,["nr_rel19_cp_ofdm_strict", ...
                "nr_rel19_ul_dfts_ofdm_strict"]);
            profile = struct("ProfileID",id, ...
                "NormativeClaimAllowed",normative, ...
                "Strict",startsWith(id,"nr_rel19_"), ...
                "TS38211",sixgr.phy.waveform.WaveformSpecificationProfile.TS38211, ...
                "TS38214",sixgr.phy.waveform.WaveformSpecificationProfile.TS38214, ...
                "TS38331",sixgr.phy.waveform.WaveformSpecificationProfile.TS38331, ...
                "IndexConvention","zero_based_waveform_indices");
        end

        function versions = environment()
            products = ver;
            toolbox = products(strcmp({products.Name},"5G Toolbox"));
            toolboxVersion = "unavailable";
            if ~isempty(toolbox)
                toolboxVersion = string(toolbox(1).Version);
            end
            versions = struct("MATLABVersion",string(version), ...
                "MATLABRelease",string(version("-release")), ...
                "ToolboxVersion",toolboxVersion);
        end
    end
end
