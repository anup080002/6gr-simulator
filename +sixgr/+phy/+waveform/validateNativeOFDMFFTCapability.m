function accounting=validateNativeOFDMFFTCapability(evidence,carrier,nfft,fs,fraction,symbolCount,carrierFrequency)
% Re-establish capability on this exact runtime; never relabel old receipts.
if nargin<7, carrierFrequency=0; end
id='sixgr:waveform:NativeFFTCapabilityBinding';
assert(isstruct(evidence)&&isscalar(evidence)&&all(isfield(evidence, ...
    {'Signature','EvidenceSHA256','Available'}))&&islogical(evidence.Available)&& ...
    isscalar(evidence.Available)&&evidence.Available&& ...
    string(evidence.Signature.MATLABRelease)==string(version('-release')),id, ...
    'Require original capability evidence from this same runtime release.');
[actual,accounting]=sixgr.phy.waveform.nativeOFDMFFTCapability( ...
    carrier,nfft,fs,fraction,symbolCount,carrierFrequency);
% JSON round-trip permits only serialization shape/string differences; all
% capability operands, measured responses, exact signature and digest agree.
assert(strcmp(jsonencode(jsondecode(jsonencode(evidence))), ...
    jsonencode(jsondecode(jsonencode(actual)))),id, ...
    'The original operator capability or runtime signature changed.');
end
