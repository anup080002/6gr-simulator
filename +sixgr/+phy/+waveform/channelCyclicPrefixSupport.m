function evidence=channelCyclicPrefixSupport(pathFilters,trimSamples,cpLengths,cpFraction)
%CHANNELCYCLICPREFIXSUPPORT Exact finite-filter support at an OFDM FFT window.
% This checks only static, unwindowed circular-convolution support. It does
% not qualify Doppler ICI, RF impairments, a receiver, or a BLER calibration.
% Retain every nonzero native filter tap; do not threshold small tails away.
arguments
    pathFilters (:,:) double {mustBeFinite}
    trimSamples (1,1) double {mustBeInteger,mustBeNonnegative}
    cpLengths double {mustBeInteger,mustBePositive,mustBeFinite}
    cpFraction (1,1) double {mustBeFinite,mustBeGreaterThanOrEqual(cpFraction,0),mustBeLessThanOrEqual(cpFraction,1)}
end
assert(~isempty(pathFilters) && ~isempty(cpLengths) && isvector(cpLengths), ...
    'sixgr:phy:waveform:MissingCPChannelSupport','Require native filters and executed CP lengths.');
nonzero=find(any(pathFilters~=0,2))-1;
assert(~isempty(nonzero),'sixgr:phy:waveform:EmptyChannelSupport','An all-zero channel has no usable propagation support.');
relative=double(nonzero)-trimSamples;
cp=double(cpLengths(:).');
fftStart=fix(cpFraction*cp);
% Each FFT sample must depend only on samples from this symbol and its CP:
% fftStart-cp <= relative filter delay <= fftStart.
earliestAllowed=fftStart-cp;
latestAllowed=fftStart;
fits=min(relative)>=earliestAllowed & max(relative)<=latestAllowed;
previous=max(0,max(relative)-fftStart);
following=max(0,fftStart-cp-min(relative));
evidence=struct('Schema',"sixgr.channel_cp_support/v1", ...
    'Source',"native_path_filter_support_and_executed_fft_window", ...
    'TrimSamples',trimSamples,'CyclicPrefixFraction',cpFraction, ...
    'CyclicPrefixLengths_samples',cp,'FFTStartWithinCP_samples',fftStart, ...
    'EarliestRelativeFilterTap_samples',min(relative), ...
    'LatestRelativeFilterTap_samples',max(relative), ...
    'EarliestAllowedTap_samples',earliestAllowed,'LatestAllowedTap_samples',latestAllowed, ...
    'CircularConvolutionSupportedPerSymbol',fits, ...
    'CircularConvolutionSupported',all(fits), ...
    'RequiredPreviousSymbolSamples',previous, ...
    'RequiredFollowingSymbolSamples',following, ...
    'ResidualISIICIIncluded',false,'StatisticalCalibrationQualified',false);
end
