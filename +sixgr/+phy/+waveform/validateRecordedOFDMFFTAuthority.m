function accounting=validateRecordedOFDMFFTAuthority(operator,carrier,nfft,fs,fraction,count,frequency,isLegacyV1)
% Explicit compatibility dispatch: existing pinned v1 remains pinned. A v2
% receipt requires a real capability; no retrofit is written to old records.
id='sixgr:waveform:RecordedFFTAuthority';
assert(islogical(isLegacyV1)&&isscalar(isLegacyV1)&&isstruct(operator)&&isscalar(operator)&& ...
    all(isfield(operator,{'RuntimeMATLABRelease','EngineUsed'}))&& ...
    string(operator.RuntimeMATLABRelease)==string(version('-release'))&& ...
    string(operator.EngineUsed)=="canonical_nrOFDMDemodulate",id, ...
    'Retain original runtime identity and native engine.');
if isLegacyV1
    assert(string(version('-release'))=="2026a" && ~isfield(operator,'NativeFFTCapability'),id, ...
        'Only the existing unchanged R2026a v1 pinned support has legacy authority.');
    accounting=struct('IsolatedProbeDemodulationsThisCall',0,'OriginalCaptureDemodulations',0, ...
        'RFExecutions',0,'ChannelExecutions',0,'CacheHit',false, ...
        'AuthorityScope',"legacy_v1_R2026a_same_runtime_pinned_no_new_capability_claim");
else
    assert(isfield(operator,'NativeFFTCapability'),id,'A v2 original operator requires its capability proof.');
    accounting=sixgr.phy.waveform.validateNativeOFDMFFTCapability(operator.NativeFFTCapability, ...
        carrier,nfft,fs,fraction,count,frequency);
    accounting.AuthorityScope="v2_original_runtime_capability_validated";
end
end
