function [signalEnergy, evidence] = measureReceivedOccupiedREEnergy( ...
        carrier, referenceWaveform, occupiedIndices, varargin)
%MEASURERECEIVEDOCCUPIEDREENERGY Measure Es on exact received occupied REs.
%   The reference waveform must be the noiseless waveform at the same
%   sample-domain plane where standalone AWGN will be added.  Indices are
%   the actual transmitter resource indices; their port dimension is
%   collapsed to unique time-frequency locations before all receive
%   branches are measured.

ip = inputParser;
ip.FunctionName = "sixgr.phy.waveform.measureReceivedOccupiedREEnergy";
ip.addRequired("carrier");
ip.addRequired("referenceWaveform", @localValidWaveform);
ip.addRequired("occupiedIndices", @localValidIndices);
ip.addParameter("SignalFamily", "data_or_reference_signal", ...
    @(v) ischar(v) || (isstring(v) && isscalar(v)));
ip.parse(carrier, referenceWaveform, occupiedIndices, varargin{:});
opt = ip.Results;

[referenceGrid, ~] = sixgr.phy.waveform.ofdmDemodulate( ...
    carrier, referenceWaveform);
K = double(carrier.NSizeGrid) * 12;
L = double(carrier.SymbolsPerSlot);
if size(referenceGrid, 1) ~= K || size(referenceGrid, 2) < L
    error("sixgr:phy:waveform:ReceivedOccupiedREGridShapeMismatch", ...
        "The demodulated reference grid does not match the transmitting carrier.");
end

indices = double(occupiedIndices(:));
indices = indices(isfinite(indices) & indices >= 1 & indices == fix(indices));
if isempty(indices)
    error("sixgr:phy:waveform:MissingOccupiedREIndices", ...
        "Exact occupied-RE energy requires nonempty transmitter resource indices.");
end
maxPort = max(1, ceil(max(indices) / max(K * L, 1)));
try
    [subcarrier, symbol, ~] = ind2sub([K, L, maxPort], indices);
catch cause
    error("sixgr:phy:waveform:InvalidOccupiedREIndices", ...
        "Occupied resource indices are incompatible with the transmitting carrier: %s", ...
        cause.message);
end
tfIndices = unique(sub2ind([K, L], subcarrier, symbol), "stable");
gridByBranch = reshape(referenceGrid(:, 1:L, :), K * L, []);
observations = gridByBranch(tfIndices, :);
finiteMask = isfinite(real(observations)) & isfinite(imag(observations));
if ~all(finiteMask, "all")
    error("sixgr:phy:waveform:NonfiniteReceivedOccupiedRE", ...
        "The noiseless received occupied-RE observations must all be finite.");
end
signalEnergy = mean(abs(double(observations(:))).^2, "omitnan");
if ~(isscalar(signalEnergy) && isfinite(signalEnergy) && signalEnergy > 0)
    error("sixgr:phy:waveform:InvalidReceivedOccupiedREEnergy", ...
        "Measured received occupied-RE energy must be positive and finite.");
end

evidence = struct( ...
    "Version", "sixgr.phy.waveform.received_occupied_re_energy/v1", ...
    "Source", "sixgr.phy.waveform.measureReceivedOccupiedREEnergy", ...
    "ExecutionClass", "shared_production_phy_truth_primitive", ...
    "ApproximationMode", "none", ...
    "ProxyUsed", false, ...
    "FallbackUsed", false, ...
    "SignalFamily", char(string(opt.SignalFamily)), ...
    "MeasurementPlane", ...
        "noiseless_received_resource_grid_post_channel_post_large_scale_pre_noise", ...
    "SignalEnergyPerOccupiedRE", double(signalEnergy), ...
    "TransmitterIndexCount", double(numel(indices)), ...
    "UniqueTimeFrequencyRECount", double(numel(tfIndices)), ...
    "ReceiveBranchCount", double(size(gridByBranch, 2)), ...
    "ObservationCount", double(numel(observations)), ...
    "ConfiguredCyclicPrefix", char(string(carrier.CyclicPrefix)), ...
    "ConfiguredSubcarrierSpacing_kHz", double(carrier.SubcarrierSpacing));
end

function tf = localValidWaveform(value)
tf = isnumeric(value) && isfloat(value) && ismatrix(value) && ...
    ~isempty(value) && size(value, 1) > 0 && all(isfinite(value), "all");
end

function tf = localValidIndices(value)
tf = isnumeric(value) && isreal(value) && ~isempty(value) && ...
    all(isfinite(value(:))) && all(value(:) >= 1) && ...
    all(value(:) == fix(value(:)));
end
