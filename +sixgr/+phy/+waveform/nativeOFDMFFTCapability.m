function [evidence,accounting]=nativeOFDMFFTCapability(carrier,nfft,fs,fraction,symbolCount,carrierFrequency)
% Public native-operator semantic probe, isolated from all original samples.
% One deterministic batched impulse demodulation proves each claimed FFT
% start/end sample is included and each representable neighbor is excluded.
% Cache reuse is exact-signature only. Probe calls are not measurement calls.
persistent keys values
if isempty(keys), keys=strings(0,1); values=cell(0,1); end
if nargin<6, carrierFrequency=0; end
id='sixgr:waveform:NativeFFTCapability';
assert(isa(carrier,'nrCarrierConfig')&&isscalar(carrier),id,'Require the exact native carrier.');
validateattributes(nfft,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(fs,{'numeric'},{'scalar','real','finite','positive'});
validateattributes(fraction,{'numeric'},{'scalar','real','finite','>=',0,'<=',1});
validateattributes(symbolCount,{'numeric'},{'scalar','real','finite','integer','positive','<=',28});
validateattributes(carrierFrequency,{'numeric'},{'scalar','real','finite'});
assert(fs==nfft*double(carrier.SubcarrierSpacing)*1000,id, ...
    'Receive resampling is unsupported by this unresampled FFT dependency contract.');
installed=ver('5g');
operatorPath=which('nrOFDMDemodulate');
assert(isscalar(installed)&&isfile(operatorPath),id,'Require the public installed 5G operator.');
signature=struct('ContractVersion',"sixgr.waveform.native_FFT_capability/v1", ...
    'MATLABRelease',string(version('-release')),'MATLABVersion',string(version), ...
    'ToolboxVersion',string(installed.Version),'Operator',"nrOFDMDemodulate", ...
    'OperatorPath',string(operatorPath),'OperatorFileSHA256',sixgr.util.sha256File(operatorPath), ...
    'NSizeGrid',double(carrier.NSizeGrid),'NStartGrid',double(carrier.NStartGrid), ...
    'NCellID',double(carrier.NCellID),'NFrame',double(carrier.NFrame),'NSlot',double(carrier.NSlot), ...
    'SubcarrierSpacing_kHz',double(carrier.SubcarrierSpacing),'CyclicPrefix',string(carrier.CyclicPrefix), ...
    'Nfft',double(nfft),'SampleRateHz',double(fs),'CyclicPrefixFraction',double(fraction), ...
    'SymbolCount',double(symbolCount),'CarrierFrequencyHz',double(carrierFrequency), ...
    'ReceiveResamplingApplied',false,'OFDMWindowingSamples',0);
key=string(sixgr.util.sha256Hex(char(jsonencode(signature))));
accounting=struct('IsolatedProbeDemodulationsThisCall',0,'OriginalCaptureDemodulations',0, ...
    'RFExecutions',0,'ChannelExecutions',0,'CacheHit',false);
hit=find(keys==key,1);
if ~isempty(hit), evidence=values{hit}; accounting.CacheHit=true; return; end
before=rng; restore=onCleanup(@()rng(before)); %#ok<NASGU>
probeCarrier=nrCarrierConfig('NSizeGrid',signature.NSizeGrid,'NStartGrid',signature.NStartGrid, ...
    'NCellID',signature.NCellID,'NFrame',signature.NFrame,'NSlot',signature.NSlot, ...
    'SubcarrierSpacing',signature.SubcarrierSpacing_kHz,'CyclicPrefix',signature.CyclicPrefix);
info=nrOFDMInfo(probeCarrier,'Nfft',double(nfft),'SampleRate',double(fs),'Windowing',0);
L=double(carrier.SymbolsPerSlot); at=mod(mod(double(carrier.NSlot), ...
    double(carrier.SlotsPerSubframe))*L+(0:double(symbolCount)-1),numel(info.SymbolLengths))+1;
lengths=reshape(double(info.SymbolLengths(at)),1,[]);
cp=reshape(double(info.CyclicPrefixLengths(at)),1,[]);
assert(all(lengths==cp+nfft),id,'Native lengths must equal CP plus the configured FFT.');
starts=[0 cumsum(lengths(1:end-1))]+fix(cp*double(fraction));
windows=[starts(:) starts(:)+double(nfft)]; count=sum(lengths);
positions=zeros(0,1); targets=zeros(0,1); expected=false(0,1); labels=strings(0,1);
for symbol=1:double(symbolCount)
    q=[windows(symbol,1),windows(symbol,2)-1,windows(symbol,1)-1,windows(symbol,2)];
    for edge=1:4
        if q(edge)<0||q(edge)>=count, continue; end % Absent capture samples cannot be consumed.
        positions(end+1,1)=q(edge); targets(end+1,1)=symbol; expected(end+1,1)=edge<=2; %#ok<AGROW>
        names=["included_first","included_last","excluded_predecessor","excluded_successor"];
        labels(end+1,1)=names(edge); %#ok<AGROW>
    end
end
probe=complex(zeros(count,numel(positions)));
probe(sub2ind(size(probe),positions+1,(1:numel(positions)).'))=1;
grid=nrOFDMDemodulate(probeCarrier,probe,'Nfft',double(nfft),'SampleRate',double(fs), ...
    'CyclicPrefixFraction',double(fraction),'CarrierFrequency',double(carrierFrequency));
accounting.IsolatedProbeDemodulationsThisCall=1;
assert(size(grid,1)==12*double(carrier.NSizeGrid)&&size(grid,2)>=symbolCount&& ...
    size(grid,3)==numel(positions)&&all(isfinite(grid),'all'),id,'Native probe returned another grid layout.');
minimum=zeros(numel(positions),1); maximum=minimum;
for k=1:numel(positions)
    magnitude=abs(double(grid(:,targets(k),k)));
    minimum(k)=min(magnitude); maximum(k)=max(magnitude);
end
tolerance=256*eps*max(1,log2(double(nfft)));
assert(all(abs(minimum(expected)-1)<=tolerance)&&all(abs(maximum(expected)-1)<=tolerance)&& ...
    all(maximum(~expected)<=tolerance),id, ...
    'Native public demodulator did not prove the exact claimed FFT inclusion/exclusion rule.');
assert(isequal(rng,before),id,'Isolated deterministic probing must not consume the global random stream.');
evidence=struct('Signature',signature,'SignatureSHA256',key,'Available',true, ...
    'FFTWindowRule',"symbol_start_plus_fix_CP_times_fraction", ...
    'SymbolLengths',lengths,'CyclicPrefixLengths',cp,'FFTIntervals',windows, ...
    'ProbeSamplePositions0',positions,'ProbeTargetSymbols1',targets,'ProbeRoles',labels, ...
    'ExcludedNeighborsOutsideCapture',4*double(symbolCount)-numel(positions), ...
    'ProbeExpectedIncluded',expected,'ProbeMinimumMagnitude',minimum,'ProbeMaximumMagnitude',maximum, ...
    'ArithmeticTolerance',tolerance,'ProbeDemodulationsToEstablishCapability',1, ...
    'OriginalCaptureDemodulations',0,'OriginalCaptureConsumed',false,'RNGUnchanged',true, ...
    'RFExecutions',0,'ChannelExecutions',0,'ReusePolicy',"process_cache_exact_signature", ...
    'Scope',"native_unresampled_CP_fraction_FFT_support_not_receiver_accuracy");
evidence.EvidenceSHA256=string(sixgr.util.sha256Hex(char(jsonencode(evidence))));
keys(end+1,1)=key; values{end+1,1}=evidence;
end
