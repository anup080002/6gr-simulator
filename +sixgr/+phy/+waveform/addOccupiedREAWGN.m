function [rxWaveform, provenance] = addOccupiedREAWGN( ...
        txWaveform, carrier, snr_dB, varargin)
%ADDOCCUPIEDREAWGN Add AWGN at an occupied-grid-RE Es/N0 reference plane.
%
% This is the common production noise primitive used by fixed-link LLS,
% FRC conformance, CSI/reference-signal studies, control/broadcast paths,
% and waveform replay adapters.  It deliberately avoids waveform-average
% power because cyclic prefix samples and unused FFT bins are not occupied
% resource-element energy.
%
%   gridNoiseVariance   = Es * 10^(-EsN0_dB/10)
%   sampleNoiseVariance = gridNoiseVariance / Gsample_to_grid
%
% Gsample_to_grid is measured for the exact carrier, cyclic-prefix, FFT,
% sample-rate, and OFDM implementation by calibrateOFDMNoiseTransform.

ip = inputParser;
ip.FunctionName = "sixgr.phy.waveform.addOccupiedREAWGN";
ip.addRequired("txWaveform", @localValidWaveform);
ip.addRequired("carrier");
ip.addRequired("snr_dB", ...
    @(v) isnumeric(v) && isreal(v) && isscalar(v) && isfinite(v));
ip.addParameter("Seed", [], @localValidSeed);
ip.addParameter("SignalEnergyPerOccupiedRE", 1, ...
    @(v) isnumeric(v) && isreal(v) && isscalar(v) && ...
    isfinite(v) && v > 0);
ip.parse(txWaveform, carrier, snr_dB, varargin{:});
opt = ip.Results;

calibration = sixgr.phy.waveform.calibrateOFDMNoiseTransform(carrier);
sampleToGridGain = double(calibration.SampleToGridNoiseVarianceGain);
if ~(isscalar(sampleToGridGain) && isfinite(sampleToGridGain) && ...
        sampleToGridGain > 0)
    error("sixgr:phy:waveform:InvalidOFDMNoiseGain", ...
        ["The calibrated OFDM sample-to-grid noise-variance gain must " ...
        "be positive and finite."]);
end

requestedEsN0_dB = double(snr_dB);
signalEnergyPerOccupiedRE = double(opt.SignalEnergyPerOccupiedRE);
gridNoiseVariance = signalEnergyPerOccupiedRE .* ...
    10.^(-requestedEsN0_dB / 10);
sampleNoiseVariance = gridNoiseVariance / sampleToGridGain;
if ~(isscalar(gridNoiseVariance) && isfinite(gridNoiseVariance) && ...
        gridNoiseVariance > 0 && isscalar(sampleNoiseVariance) && ...
        isfinite(sampleNoiseVariance) && sampleNoiseVariance > 0)
    error("sixgr:phy:waveform:InvalidOccupiedRENoiseVariance", ...
        "The requested occupied-RE Es/N0 produced an invalid variance.");
end

seed = opt.Seed;
if isempty(seed)
    realNoise = randn(size(txWaveform), "like", real(txWaveform));
    imagNoise = randn(size(txWaveform), "like", real(txWaveform));
else
    stream = RandStream("mt19937ar", "Seed", double(seed));
    realNoise = randn(stream, size(txWaveform));
    imagNoise = randn(stream, size(txWaveform));
    realNoise = cast(realNoise, "like", real(txWaveform));
    imagNoise = cast(imagNoise, "like", real(txWaveform));
end
noise = sqrt(sampleNoiseVariance / 2) .* ...
    complex(realNoise, imagNoise);
rxWaveform = txWaveform + cast(noise, "like", txWaveform);

provenance = struct( ...
    "Version", "sixgr.phy.waveform.occupied_re_awgn/v1", ...
    "Source", "sixgr.phy.waveform.addOccupiedREAWGN", ...
    "ExecutionClass", "shared_production_phy_truth_primitive", ...
    "ApproximationMode", "none", ...
    "ProxyUsed", false, "FallbackUsed", false, ...
    "NoiseKind", ...
        "independent_zero_mean_circular_complex_time_domain_awgn", ...
    "RequestedEsN0_dB", requestedEsN0_dB, ...
    "SNRReferencePlane", "occupied_resource_grid_re_pre_equalization", ...
    "SNRDefinition", ...
        "Es/N0 for disclosed occupied-grid-RE symbol energy; N0 is complex grid-domain noise variance after canonical OFDM demodulation", ...
    "SignalEnergyPerOccupiedRE", signalEnergyPerOccupiedRE, ...
    "GridNoiseVariance", gridNoiseVariance, ...
    "SampleNoiseVariance", sampleNoiseVariance, ...
    "ComplexVarianceDefinition", "E[abs(n)^2]", ...
    "SampleToGridNoiseVarianceGain", sampleToGridGain, ...
    "SampleToGridNoiseVarianceGainSource", ...
        string(calibration.SampleToGridNoiseVarianceGainSource), ...
    "VarianceEquation", ...
        "sampleNoiseVariance = SignalEnergyPerOccupiedRE*10^(-RequestedEsN0_dB/10)/SampleToGridNoiseVarianceGain", ...
    "WaveformPowerUsed", false, ...
    "CyclicPrefixPowerUsed", false, ...
    "UnusedFFTBinPowerUsed", false, ...
    "ConfiguredCyclicPrefix", string(carrier.CyclicPrefix), ...
    "ConfiguredSubcarrierSpacing_kHz", ...
        double(carrier.SubcarrierSpacing), ...
    "NumTimeSamples", size(txWaveform, 1), ...
    "NumRxColumns", size(txWaveform, 2), ...
    "SeedApplied", ~isempty(seed), ...
    "Seed", localSeedValue(seed), ...
    "RandomStream", localStreamName(seed), ...
    "CallerGlobalRNGConsumed", isempty(seed), ...
    "CallerGlobalRNGStatePreserved", ~isempty(seed), ...
    "OFDMCalibrationVersion", string(calibration.Version));
end

function tf = localValidWaveform(value)
tf = isnumeric(value) && isfloat(value) && ismatrix(value) && ...
    ~isempty(value) && size(value, 1) > 0 && all(isfinite(value), "all");
end

function tf = localValidSeed(value)
tf = isempty(value) || (isnumeric(value) && isreal(value) && ...
    isscalar(value) && isfinite(value) && value == fix(value) && ...
    value >= 0 && value <= 2^32 - 1);
end

function value = localSeedValue(seed)
if isempty(seed), value = NaN; else, value = double(seed); end
end

function value = localStreamName(seed)
if isempty(seed)
    value = "caller_global_stream";
else
    value = "local_mt19937ar";
end
end
