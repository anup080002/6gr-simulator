function timing = estimateSRSDelayTiming(rx, tx, srsCfg)
%ESTIMATESRSDELAYTIMING Estimate SRS timing from waveform correlation.

ref = tx.Waveform(:);
obs = rx.RxWaveform(:);
est = NaN;
metric = NaN;
if ~isempty(ref) && ~isempty(obs)
    c = abs(conv(obs, conj(flipud(ref)), "full"));
    [peak, idx] = max(c);
    est = double(idx - numel(ref));
    den = max(norm(obs) * norm(ref), eps);
    metric = double(peak / den);
end
err = est - double(rx.InjectedTimingOffsetSamples);
avail = isfinite(est) && abs(err) <= double(srsCfg.TimingToleranceSamples);
row = struct("RunId", string(srsCfg.RunId), "TrialId", NaN, ...
    "TimingEstimateAttempted", true, "SRSTimingEstimateAvailable", logical(avail), ...
    "EstimatedTimingOffsetSamples", double(est), ...
    "InjectedTimingOffsetSamples", double(rx.InjectedTimingOffsetSamples), ...
    "TimingErrorSamples", double(err), "TimingMetric", double(metric), ...
    "TimingToleranceSamples", double(srsCfg.TimingToleranceSamples), ...
    "Status", string(sixgr.phy.srs.localTernary(avail, "timing_estimate_available", "timing_estimate_unavailable")), ...
    "ConfigHash", string(srsCfg.ConfigHash), "TruthStatus", "real_lls_evidence");
timing = struct("TimingEstimateAttempted", true, "SRSTimingEstimateAvailable", logical(avail), ...
    "EstimatedTimingOffsetSamples", double(est), "TimingErrorSamples", double(err), ...
    "Metric", double(metric), "Table", struct2table(row, "AsArray", true));
end
