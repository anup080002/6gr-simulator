function [evidence,probeAccounting]=srsAntennaPowerFFTSupport(carrier,ofdm,timing,first,stop,support,source)
% Exact original raw-sample windows of the native SRS power demodulation.
% A runtime-isolated public operator probe qualifies CP-fraction support.
% This records support only. It never reacquires timing or processes IQ.
id='sixgr:srs:AntennaPowerFFTSupport';
if nargin<7, source="original_noisy_preRF_measurement_native_demodulation"; end
assert(isscalar(string(source)) && any(string(source)==[ ...
    "original_noisy_preRF_measurement_native_demodulation", ...
    "recorded_practical_RX_clock_reference_native_demodulation"]),id, ...
    'Declare the actual observation clock; do not relabel a different FFT support.');
assert(isa(carrier,'nrCarrierConfig')&&isscalar(carrier)&&isstruct(ofdm)&& ...
    isscalar(ofdm)&&all(isfield(ofdm,{'EngineUsed','Nfft','SampleRate', ...
    'CyclicPrefixFraction','SymbolLengths','CyclicPrefixLengths','WaveformSize', ...
    'OFDMWindowingSamples','WaveformSHA256','GridSHA256'})),id, ...
    'Retain the original actual native demodulation receipt and carrier.');
assert(string(ofdm.EngineUsed)=="canonical_nrOFDMDemodulate",id, ...
    'Only the recorded native demodulator can carry native support.');
validateattributes(first,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(stop,{'numeric'},{'scalar','real','finite','integer','>',first});
validateattributes(ofdm.Nfft,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(ofdm.CyclicPrefixFraction,{'numeric'},{'scalar','real','finite','>=',0,'<=',1});
assert(ofdm.SampleRate==ofdm.Nfft*double(carrier.SubcarrierSpacing)*1000&& ...
    ofdm.OFDMWindowingSamples==0,id, ...
    'Resampling or another receive window requires its own actual dependency operator.');
assert(isstruct(timing)&&isscalar(timing)&&all(isfield(timing, ...
    {'AppliedTimingCorrectionSamples','DemodulatedSampleCount','OracleTimingUsed','ReceiverZeroPaddingUsed'}))&& ...
    ~timing.OracleTimingUsed&&~timing.ReceiverZeroPaddingUsed,id, ...
    'Use the recorded noisy-measurement timing without padding or reference-derived acquisition.');
offset=double(timing.AppliedTimingCorrectionSamples);
validateattributes(offset,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(support,{'numeric'},{'2d','nonempty','real','finite','integer','nonnegative'});
if isvector(support)&&numel(support)==2, support=reshape(support,1,2); end
L=double(carrier.SymbolsPerSlot); K=12*double(carrier.NSizeGrid);
assert(size(support,2)==2&&all(support(:,1)<K)&&all(support(:,2)<L)&& ...
    isequal(support,unique(support,'rows','sorted')),id,'Retain the exact unique physical pilot RE union.');
localSlot=mod(double(carrier.NSlot),double(carrier.SlotsPerSubframe));
slotIndices=localSlot*L+(1:L);
lengths=double(ofdm.SymbolLengths(slotIndices)); lengths=lengths(:).';
cp=double(ofdm.CyclicPrefixLengths(slotIndices)); cp=cp(:).';
assert(all(lengths==cp+ofdm.Nfft)&&sum(lengths)==timing.DemodulatedSampleCount&& ...
    ofdm.WaveformSize(1)==timing.DemodulatedSampleCount&& ...
    first+offset+sum(lengths)<=stop,id,'No selected FFT may use absent or padded capture samples.');
[capability,probeAccounting]=sixgr.phy.waveform.nativeOFDMFFTCapability(carrier, ...
    double(ofdm.Nfft),double(ofdm.SampleRate),double(ofdm.CyclicPrefixFraction),L,0);
assert(isequal(double(capability.SymbolLengths(:)),lengths(:)) && ...
    isequal(double(capability.CyclicPrefixLengths(:)),cp(:)),id, ...
    'Capability geometry must match the original executed native receipt.');
symbols=unique(double(support(:,2))).';
starts=[0 cumsum(lengths(1:end-1))];
fftStart=first+offset+starts(symbols+1)+fix(cp(symbols+1)*double(ofdm.CyclicPrefixFraction));
windows=[fftStart(:) fftStart(:)+double(ofdm.Nfft)];
assert(all(windows(:,1)>=first)&&all(windows(:,2)<=stop),id,'FFT support leaves the completed capture.');
evidence=struct('ContractVersion',"sixgr.srs.measured_native_FFT_support/v2", ...
    'Source',string(source),'NativeFFTCapability',capability, ...
    'CapabilityProbeAccountingScope',"isolated_proof_establishment_not_original_capture_demodulations", ...
    'RuntimeMATLABRelease',string(version('-release')),'EngineUsed',string(ofdm.EngineUsed), ...
    'ObservationStartSample',first,'ObservationEndSampleExclusive',stop, ...
    'SampleRateHz',double(ofdm.SampleRate),'Nfft',double(ofdm.Nfft), ...
    'CarrierSlot',double(carrier.NSlot),'SymbolsPerSlot',L,'SlotsPerSubframe',double(carrier.SlotsPerSubframe), ...
    'CyclicPrefixFraction',double(ofdm.CyclicPrefixFraction), ...
    'CyclicPrefixLengths',cp,'SymbolLengths',lengths, ...
    'AppliedTimingCorrectionSamples',offset,'AlignedSampleCount',sum(lengths), ...
    'FFTWindowRule',"symbol_start_plus_fix_CP_times_fraction", ...
    'FFTIntervals',windows,'SelectedSymbols0',symbols, ...
    'ResourceSupportSubcarrier0Symbol0',support,'ReceiveResamplingApplied',false, ...
    'OFDMWindowingSamples',0,'AlignedWaveformSHA256',string(ofdm.WaveformSHA256), ...
    'GridSHA256',string(ofdm.GridSHA256),'ReferenceTimingAcquisitionUsed',false);
end
