function score = scoreSRSDetection(srsCfg, rx, det, ch, timing, varargin)
%SCORESRSDETECTION Build row-level strict SRS trial verdict.

p = inputParser;
addParameter(p, "TrialId", 1, @(x) isnumeric(x) && isscalar(x));
addParameter(p, "TrialType", "positive_awgn", @(x) ischar(x) || isstring(x));
addParameter(p, "NegativeExpected", false, @(x) islogical(x) || isnumeric(x));
parse(p, varargin{:});
trialId = round(double(p.Results.TrialId));
trialType = string(p.Results.TrialType);
negativeExpected = logical(p.Results.NegativeExpected);
coverage = det.Coverage;
trigger = sixgr.phy.srs.resolveSRSTrigger(srsCfg);
configStrictValid = logical(sixgr.util.structGet(srsCfg.StrictValidation, "StrictValid", false));
strictOk = logical(det.DetectionSuccess) && logical(ch.SRSChannelEstimateAvailable) && ...
    logical(timing.SRSTimingEstimateAvailable) && logical(coverage.ConfiguredBandClaimValid) && ...
    (~logical(srsCfg.FullCarrierSoundingRequired) || logical(coverage.FullCarrierClaimValid)) && ...
    configStrictValid && logical(trigger.TriggerValid);
if negativeExpected
    negativeOk = ~strictOk;
else
    negativeOk = false;
end
if strictOk
    status = "PASS";
    failure = "";
else
    status = "FAIL";
    failure = localFailureReason(det, ch, timing, coverage, srsCfg);
end
row = struct("RunId", string(srsCfg.RunId), "ScenarioName", string(srsCfg.ScenarioName), ...
    "TrialId", double(trialId), "TrialType", trialType, "CellId", double(srsCfg.CellId), ...
    "UEId", double(srsCfg.UEId), "ConfigHash", string(srsCfg.ConfigHash), ...
    "ResourceSetId", double(srsCfg.ResourceSetId), "ResourceId", double(srsCfg.ResourceId), ...
    "ResourceSetUsage", string(srsCfg.ResourceSetUsage), "ResourceType", string(srsCfg.ResourceType), ...
    "TriggerValid", logical(trigger.TriggerValid), "TriggerSource", string(trigger.TriggerSource), ...
    "TriggerReferenceId", string(trigger.TriggerReferenceId), ...
    "DetectionAttempted", true, "DetectionSuccess", logical(det.DetectionSuccess), ...
    "DetectionMetric", double(det.DetectionMetric), "ResourceExtractionAttempted", true, ...
    "ResourceExtractionAvailable", logical(det.Extracted.ExtractionAvailable), ...
    "ChannelEstimateAttempted", true, "SRSChannelEstimateAvailable", logical(ch.SRSChannelEstimateAvailable), ...
    "NMSE_dB", double(ch.NMSE_dB), "WidebandSRSSINR_dB", double(ch.WidebandSRSSINR_dB), ...
    "NMSEReferenceSource", string(sixgr.util.structGet(ch, "NMSEReferenceSource", "")), ...
    "SRSRITPMIValid", logical(sixgr.util.structGet(ch, "SRSRITPMI.Valid", false)), ...
    "RIEstimate", double(sixgr.util.structGet(ch, "RIEstimate", NaN)), ...
    "TPMIEstimate", double(sixgr.util.structGet(ch, "TPMIEstimate", NaN)), ...
    "RISource", string(sixgr.util.structGet(ch, "RISource", "")), ...
    "TPMISource", string(sixgr.util.structGet(ch, "TPMISource", "")), ...
    "TPMICandidateCount", double(sixgr.util.structGet(ch, "TPMICandidateCount", NaN)), ...
    "TPMIMutualInformation", double(sixgr.util.structGet(ch, "TPMIMutualInformation", NaN)), ...
    "RIConditionNumber_dB", double(sixgr.util.structGet(ch, "RIConditionNumber_dB", NaN)), ...
    "TimingEstimateAttempted", true, "SRSTimingEstimateAvailable", logical(timing.SRSTimingEstimateAvailable), ...
    "EstimatedTimingOffsetSamples", double(timing.EstimatedTimingOffsetSamples), ...
    "InjectedTimingOffsetSamples", double(rx.InjectedTimingOffsetSamples), ...
    "TimingErrorSamples", double(timing.TimingErrorSamples), ...
    "ExpectedRECount", double(coverage.ExpectedRECount), "ObservedRECount", double(coverage.ObservedRECount), ...
    "ExpectedRBStart", double(srsCfg.ExpectedRBStart), "ExpectedNumRB", double(srsCfg.ExpectedNumRB), ...
    "ObservedPRBStart", double(coverage.PRBStart), "ObservedPRBEnd", double(coverage.PRBEnd), ...
    "ObservedPRBCount", double(coverage.OccupiedPRBCount), ...
    "CoveragePercent", double(coverage.CoveragePercent), ...
    "CoverageRequirement", string(srsCfg.CoverageRequirement), ...
    "BandwidthCoverageStatus", string(coverage.BandwidthCoverageStatus), ...
    "FullCarrierSoundingRequired", logical(srsCfg.FullCarrierSoundingRequired), ...
    "FullCarrierClaimValid", logical(coverage.FullCarrierClaimValid), ...
    "ConfiguredBandClaimValid", logical(coverage.ConfiguredBandClaimValid), ...
    "AppliedAWGNSNR_dB", double(rx.AppliedAWGNSNR_dB), ...
    "NoiseVariance", double(rx.NoiseVariance), "ChannelModel", string(rx.ChannelModel), ...
    "ChannelFadingApplied", logical(rx.ChannelFadingApplied), ...
    "ProxyUsed", false, "Skipped", false, "ToolboxMissing", false, ...
    "UsedOracleFields", "", "StrictOk", logical(strictOk), ...
    "NegativeExpectedOk", logical(negativeOk), "Status", status, ...
    "FailureReason", string(failure), "TruthStatus", "real_lls_evidence");
score = struct("StrictOk", logical(strictOk), "TrialRow", row);
end

function reason = localFailureReason(det, ch, timing, coverage, srsCfg)
parts = strings(0, 1);
trigger = sixgr.phy.srs.resolveSRSTrigger(srsCfg);
configStrictValid = logical(sixgr.util.structGet(srsCfg.StrictValidation, "StrictValid", false));
if ~configStrictValid, parts(end+1, 1) = "srs_strict_config_invalid"; end %#ok<AGROW>
if ~logical(trigger.TriggerValid), parts(end+1, 1) = string(trigger.FailureReason); end %#ok<AGROW>
if ~logical(det.DetectionSuccess), parts(end+1, 1) = "srs_detection_failed"; end %#ok<AGROW>
if ~logical(ch.SRSChannelEstimateAvailable), parts(end+1, 1) = "srs_channel_estimate_unavailable"; end %#ok<AGROW>
if ~logical(timing.SRSTimingEstimateAvailable), parts(end+1, 1) = "srs_timing_estimate_unavailable"; end %#ok<AGROW>
if ~logical(coverage.ConfiguredBandClaimValid), parts(end+1, 1) = "srs_configured_band_claim_invalid"; end %#ok<AGROW>
if logical(srsCfg.FullCarrierSoundingRequired) && ~logical(coverage.FullCarrierClaimValid)
    parts(end+1, 1) = "srs_partial_band_claimed_full"; %#ok<AGROW>
end
reason = strjoin(parts, "|");
end
