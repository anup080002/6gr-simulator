function [out,pairs]=measureReceivedPilotEVM(received,desired,indices,numPorts,slot0,evidence)
% Post-reception diagnostic on actual SRS REs, not equalized port EVM.
% Multiple CDM ports may occupy the same received RE. Count that RE once
% per physical RX branch, not once per logical transmitted SRS port.
out=struct('EVM_rms',NaN,'EVMErrorEnergy',NaN,'EVMReferenceEnergy',NaN, ...
    'EVMSymbolCount',0,'EVMEnergyUnit',"sum_squared_complex_symbol_amplitude_not_joules", ...
    'EVMReferenceSource',"unavailable",'EVMReferencePlane',"unavailable", ...
    'EVMValueStatus',"NOT_AVAILABLE",'EVMComputationDomain',"received_resource_elements");
pairs=struct([]);
if nargin==0, return; end
source=string(evidence.Source);
isolated=source=="same_executed_isolated_emitted_SRS_received_pilot_grid" && ...
    isequal(sixgr.util.structGet(evidence,'IsolatedComponentProved',false),true);
assert((source=="same_executed_desired_link_received_pilot_grid" || isolated) && ...
    ~evidence.ReceiverEstimatorInput && ~evidence.GainOrPhaseFitted && ...
    evidence.AdditionalChannelExecutions==0 && evidence.AdditionalRFExecutions==0 && ...
    isscalar(string(evidence.ReferencePlane)) && strlength(string(evidence.ReferencePlane))>0, ...
    'sixgr:phy:srs:InvalidEVMAuthority', ...
    'Use independent same-execution pilot samples only after practical reception.');
assert(isnumeric(received) && isnumeric(desired) && ndims(received)<=3 && ...
    isequal(size(received),size(desired)) && ~isempty(received), ...
    'sixgr:phy:srs:EVMPilotGridMismatch','Compare every recorded RX branch on the same grid.');
K=size(received,1); L=size(received,2); R=size(received,3);
validateattributes(numPorts,{'numeric'},{'scalar','integer','positive','finite'});
validateattributes(slot0,{'numeric'},{'scalar','integer','nonnegative','finite'});
ind=double(indices(:));
assert(~isempty(ind) && all(isfinite(ind) & ind==fix(ind) & ind>=1 & ind<=K*L*numPorts) && ...
    numel(unique(ind))==numel(ind), ...
    'sixgr:phy:srs:InvalidEVMPilotResources','Retain exact one-based logical-port RE identities.');
resources=unique(mod(ind-1,K*L)+1);
rx=reshape(received,K*L,R); ref=reshape(desired,K*L,R);
rx=rx(resources,:); ref=ref(resources,:);
assert(all(isfinite(rx),'all') && all(isfinite(ref),'all') && sum(abs(ref).^2,'all')>0, ...
    'sixgr:phy:srs:MissingEVMPilotSamples','Do not discard missing samples or invent a reference.');
out.EVMErrorEnergy=sum(abs(rx-ref).^2,'all');
out.EVMReferenceEnergy=sum(abs(ref).^2,'all');
out.EVM_rms=sqrt(out.EVMErrorEnergy/out.EVMReferenceEnergy);
out.EVMSymbolCount=numel(rx);
out.EVMReferenceSource=evidence.Source;
out.EVMReferencePlane=string(evidence.ReferencePlane);
out.EVMValueStatus="MEASURED_PAIRED_RECEIVED_PILOT_GRID_NOT_RF_CONFORMANCE";
for branch=1:R
    pair=struct('SignalName',"SRS", ...
        'ObservationID',"received_SRS_resource_slot0_"+string(slot0), ...
        'PortIndex',branch-1,'PortRole',"physical_RX_branch_not_equalized_layer", ...
        'SampleIndex',resources-1,'ReferenceReal',real(ref(:,branch)), ...
        'ReferenceImag',imag(ref(:,branch)),'MeasuredReal',real(rx(:,branch)), ...
        'MeasuredImag',imag(rx(:,branch)),'ReceiverUsesScoringReference',false, ...
        'GainOrPhaseFitted',false,'EVMDefinition',"reference_normalized_paired_symbol_evm", ...
        'AlignmentSource',"recorded_receiver_timing_and_frequency_clock_no_fit", ...
        'ReferenceSource',evidence.Source,'MeasurementDomain',"received_resource_elements", ...
        'ReferencePlane',out.EVMReferencePlane);
    if isempty(pairs), pairs=pair; else, pairs(branch)=pair; end %#ok<AGROW>
end
end
