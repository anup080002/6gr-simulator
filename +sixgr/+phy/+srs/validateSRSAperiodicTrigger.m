function T = validateSRSAperiodicTrigger(srsCfg)
%VALIDATESRSAPERIODICTRIGGER Validate decoded-control provenance for aperiodic SRS.

tr = sixgr.phy.srs.resolveSRSTrigger(srsCfg);
T = struct2table(struct("RunId", string(srsCfg.RunId), ...
    "ResourceType", string(srsCfg.ResourceType), ...
    "TriggerAttempted", logical(tr.TriggerAttempted), ...
    "TriggerValid", logical(tr.TriggerValid), ...
    "TriggerSource", string(tr.TriggerSource), ...
    "TriggerReferenceId", string(tr.TriggerReferenceId), ...
    "FailureReason", string(tr.FailureReason), ...
    "ConfigHash", string(srsCfg.ConfigHash), ...
    "TruthStatus", "real_lls_evidence"), "AsArray", true);
end
