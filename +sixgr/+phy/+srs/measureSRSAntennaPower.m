function out = measureSRSAntennaPower(carrier,srs,observation,replay,searchWindow,resource,plane,pathPolicy)
%MEASURESRSANTENNAPOWER Independent SRS power from an actual antenna capture.
% TS 38.215 V18.4.0 5.2.5 defines linear RE power averaging and a diversity
% lower bound. Maximum-branch selection implements that bound; it is not a
% claim that 3GPP mandates this estimator or that accuracy is qualified.
% The legacy plane is the retained internal physical-element input. When
% original executed identity wiring is present, it also establishes modeled
% combined receiver branches. Hardware/accuracy qualification is independent
% and is not required merely to calculate modeled branch-plane RSRP.
% No post-RF gain inversion, clean channel reference, replay or feedback
% input is used. The practical post-RF SRS channel estimate stays separate.
% With no inputs, return the fixed publication schema (no observed values).
out=struct('SRS_RSRP_dBm',NaN,'SRSRSRPPerReceiveAntenna_dBm',zeros(1,0), ...
    'SRSAbsolutePowerAvailable',false,'SRSAbsolutePowerStatus',"not_available_no_antenna_observation", ...
    'SRSAbsolutePowerSource',"",'SRSAbsolutePowerReferencePlane',"", ...
    'SRSAbsolutePowerAggregation',"",'SRSAbsolutePowerBranchMean_dBm',NaN, ...
    'SRSAbsolutePowerSelectedBranch0',NaN,'SRSAbsolutePowerResourceID',NaN, ...
    'SRSAbsolutePowerEvidenceJSON',"",'SRSAbsolutePowerEvidenceSHA256',"", ...
    'SRSAbsolutePowerErrorIdentifier',"",'SRSAbsolutePowerAccuracyQualified',false);
pathDefaults=sixgr.phy.srs.srsPathPowerEvidence();
for field=string(fieldnames(pathDefaults)).', out.(field)=pathDefaults.(field); end
if nargin==0, return; end
assert(any(nargin==[7 8]),'sixgr:srs:AntennaPowerArguments', ...
    'Supply the complete actual observation, original execution and installed resource.');
if nargin<8, pathPolicy=struct('Enabled',false); end
if pathPolicy.Enabled, out.SRSPathPowerStatus="unavailable_no_completed_pre_RX_observation"; end
if isempty(observation), return; end
try
    assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && ...
        isscalar(observation) && observation.isComplete(), ...
        'sixgr:srs:AntennaPowerObservation','A complete actual antenna observation is required.');
    assert(isstruct(replay) && isscalar(replay) && all(isfield(replay, ...
        {'ReceiverID','RuntimeChannelStartSample','RuntimeChannelEndSample', ...
        'ReceiveStreamExecutionSegments','WaveformAmplitudeUnit'})), ...
        'sixgr:srs:AntennaPowerExecution','Retain the original physical RX execution receipt.');
    unit=string(replay.WaveformAmplitudeUnit);
    if unit~="sqrt_mW"
        out.SRSAbsolutePowerStatus="not_available_nonabsolute_executed_sample_unit";
        return;
    end
    rxID=string(replay.ReceiverID);
    assert(isstruct(plane) && isscalar(plane) && ...
        all(isfield(plane,{'ReceiverID','ObservationID','Observation'})) && ...
        string(plane.ReceiverID)==rxID+":pre_rf" && ...
        isscalar(string(plane.ObservationID)) && strlength(string(plane.ObservationID))>0 && ...
        isa(plane.Observation,'sixgr.phy.waveform.WaveformObservationBuffer') && ...
        observation==plane.Observation, ...
        'sixgr:srs:AntennaPowerPlane','Use the exact original pre-RF plane, never a same-shaped substitute.');
    assert(isscalar(rxID) && startsWith(rxID,"gnb_") && endsWith(rxID,"_rx") && ...
        observation.StartSample==replay.RuntimeChannelStartSample && ...
        observation.EndSampleExclusive==replay.RuntimeChannelEndSample, ...
        'sixgr:srs:AntennaPowerIdentity','The pre-RF capture must match the executed gNB endpoint/clock.');
    segments=replay.ReceiveStreamExecutionSegments;
    assert(iscell(segments) && ~isempty(segments), ...
        'sixgr:srs:AntennaPowerExecution','Missing original execution intervals.');
    intervals=zeros(numel(segments),2); epoch=NaN;
    for k=1:numel(segments)
        segment=segments{k}; execution=segment.Execution;
        intervals(k,:)=[segment.StartSample segment.EndSampleExclusive];
        assert(execution.StartSample<=segment.StartSample && ...
            execution.EndSampleExclusive>=segment.EndSampleExclusive && ...
            execution.SampleRateHz==observation.SampleRateHz && ...
            string(execution.Source)=="composed_tx_retained_rf_per_link_channel_sum_receiver_noise_rf" && ...
            string(execution.ApproximationMode)=="none", ...
            'sixgr:srs:AntennaPowerExecution','Use exact shared physical execution, not reconstructed samples.');
        validateattributes(execution.ConfigurationEpoch,{'numeric'}, ...
            {'scalar','real','integer','finite','nonnegative'});
        if k==1, epoch=execution.ConfigurationEpoch; end
        assert(execution.ConfigurationEpoch==epoch, ...
            'sixgr:srs:AntennaPowerEpoch','Do not pool distinct physical execution epochs.');
        match=find(string({execution.RX.ID})==rxID);
        assert(isscalar(match) && string(execution.RX(match).Replay.WaveformAmplitudeUnit)==unit, ...
            'sixgr:srs:AntennaPowerEndpoint','Every original segment must bind this endpoint and absolute unit.');
    end
    assert(intervals(1,1)<=observation.StartSample && ...
        intervals(end,2)>=observation.EndSampleExclusive && ...
        all(intervals(:,2)>intervals(:,1)) && ...
        all(intervals(2:end,1)==intervals(1:end-1,2)), ...
        'sixgr:srs:AntennaPowerCoverage','Original RX execution must continuously cover the capture.');
    branchEvidence=sixgr.rf.validateReceiveBranchObservation(observation,replay, ...
        sixgr.util.structGet(plane,'ReceiveBranchLayout',struct()));
    assert(isstruct(resource) && isscalar(resource) && ...
        all(isfield(resource,{'ResourceID','ConfigHash'})), ...
        'sixgr:srs:AntennaPowerResource','Bind the actual installed SRS resource/configuration.');
    validateattributes(resource.ResourceID,{'numeric'},{'scalar','real','integer','finite','nonnegative'});
    assert(isscalar(string(resource.ConfigHash)) && strlength(string(resource.ConfigHash))>0, ...
        'sixgr:srs:AntennaPowerResource','Missing installed SRS configuration digest.');
    native=nrOFDMInfo(carrier);
    assert(native.SampleRate==observation.SampleRateHz, ...
        'sixgr:srs:AntennaPowerSampleRate','Use the actual capture native OFDM clock.');
    indices=nrSRSIndices(carrier,srs); symbols=nrSRS(carrier,srs);
    % Acquisition runs independently on the noisy antenna samples. Do not
    % borrow the post-RF offset (which can include RX-chain delay).
    [aligned,timing]=sixgr.phy.sync.alignULReferenceObservation( ...
        carrier,observation.readComplete(),indices,symbols,searchWindow);
    [grid,ofdm]=sixgr.phy.waveform.ofdmDemodulate(carrier,aligned);
    assert(ofdm.EngineUsed=="canonical_nrOFDMDemodulate" && ...
        ofdm.SampleRate==observation.SampleRateHz && ofdm.Nfft==native.Nfft, ...
        'sixgr:srs:AntennaPowerOFDM','Retain the native FFT scaling of this observation.');
    K=size(grid,1); L=size(grid,2); R=size(grid,3); P=double(srs.NumSRSPorts);
    [subcarrier,symbol,port]=ind2sub([K,L,P],double(indices(:)));
    refs=symbols(:); support=unique([subcarrier symbol],'rows','sorted');
    signal=complex(zeros(K*L,R,'like',grid));
    perPortEnergy=zeros(P,R); perPortCount=zeros(P,1);
    pathResponse=[]; pathNoise=[];
    if pathPolicy.Enabled
        pathResponse=complex(nan(numel(indices),R)); pathNoise=nan(numel(indices),R);
    end
    cdm=sixgr.phy.srs.resolveCDMLengths(srs);
    % Per-symbol estimation preserves hopping/repetition support. It does
    % not infer a scalar full-grid channel on a fading channel.
    for sym=unique(symbol(:)).'
        selected=symbol==sym;
        [estimate,estimatedNoise]=nrChannelEstimate(carrier,grid,indices(selected),refs(selected), ...
            'CDMLengths',cdm,'AveragingWindow',[0 1]);
        for p=1:P
            use=selected & port==p; count=nnz(use);
            if count==0, continue; end
            re=sub2ind([K,L],subcarrier(use),symbol(use));
            perPortCount(p)=perPortCount(p)+count;
            for r=1:R
                hidx=sub2ind([K,L,R,P],subcarrier(use),symbol(use), ...
                    repmat(r,count,1),repmat(p,count,1));
                contribution=estimate(hidx).*refs(use);
                if pathPolicy.Enabled
                    pathResponse(use,r)=estimate(hidx).*abs(refs(use));
                    pathNoise(use,r)=estimatedNoise;
                end
                assert(all(isfinite(contribution)), ...
                    'sixgr:srs:AntennaPowerEstimate','Every configured SRS RE must have a finite estimate.');
                % Sum coincident port signals before taking physical RE
                % power. Averaging port powers would divide by port count.
                signal(re,r)=signal(re,r)+contribution;
                perPortEnergy(p,r)=perPortEnergy(p,r)+sum(abs(double(contribution)).^2);
            end
        end
    end
    occupied=sub2ind([K,L],support(:,1),support(:,2));
    scale=double(ofdm.Nfft)*sqrt(1000); % raw FFT sqrt(mW) -> sqrt(W)
    perBranchW=mean(abs(double(signal(occupied,:))/scale).^2,1);
    assert(all(isfinite(perBranchW) & perBranchW>=0) && any(perBranchW>0), ...
        'sixgr:srs:AntennaPowerUnavailable','No finite positive received SRS power.');
    [reported,branch]=max(perBranchW);
    perPortW=perPortEnergy./perPortCount/(scale^2);
    evidence=struct('Version',"sixgr.srs.antenna_power/v1", ...
        'Definition',"TS_38.215_V18.4.0_5.2.5_UL_SRS_RSRP", ...
        'ReferencePlane',"internal_physical_receive_element_before_RX_front_end", ...
        'ReferencePointApplicability',"internal_element_measurement_not_standardized_1O_or_2O_UL_SRS_RSRP_qualification", ...
        'Aggregation',"maximum_branch_selection_satisfies_diversity_lower_bound", ...
        'Estimator',"independent_preRF_nrChannelEstimate_per_symbol_known_SRS_reconstruction", ...
        'ReceiverID',rxID,'PlaneID',rxID+":pre_rf", ...
        'ObservationID',string(plane.ObservationID), ...
        'ObservationStartSample',observation.StartSample, ...
        'ObservationEndSampleExclusive',observation.EndSampleExclusive, ...
        'ObservationSampleRateHz',observation.SampleRateHz, ...
        'ObservationSHA256',observation.sampleHash(), ...
        'PhysicalConfigurationEpoch',epoch,'ExecutionIntervals',intervals, ...
        'WaveformAmplitudeUnit',unit,'Resource',resource, ...
        'ResourceSupportSubcarrier0Symbol0',support-1,'SRSNumPorts',P, ...
        'ReferenceSymbolSHA256',sixgr.phy.waveform.WaveformHash.numeric(symbols), ...
        'ReceiveBranchIndices0',0:R-1,'PerReceiveBranch_W',perBranchW, ...
        'PerPortReceiveBranch_W',perPortW,'MappedRECountPerPort',perPortCount, ...
        'UniquePhysicalRECount',size(support,1),'Reported_W',reported, ...
        'EngineeringBranchMean_W',mean(perBranchW),'SelectedBranch0',branch-1, ...
        'Nfft',ofdm.Nfft,'RawGridScaleToSqrtW',1/scale, ...
        'Timing',timing,'AlignedWaveformSHA256',ofdm.WaveformSHA256, ...
        'ReceivedGridSHA256',ofdm.GridSHA256,'AccuracyQualified',false, ...
        'DetectedPathPowerMeasured',false,'PostRFEstimateConsumed',false, ...
        'TruthChannelConsumed',false,'ReceiverFeedbackInput',false);
    evidence.ReceiveBranchBinding=branchEvidence;
    if branchEvidence.Available
        evidence.Version="sixgr.srs.antenna_power/v2";
        evidence.ReferencePlane=branchEvidence.ReferencePlane;
        evidence.ReferencePointApplicability= ...
            "modeled_identity_combined_receiver_branches_not_hardware_or_accuracy_qualification";
    end
    % Dependency qualification is optional. An unsupported native support
    % operator must not erase an otherwise valid noisy power measurement.
    evidence.FFTSupportAvailable=false; evidence.FFTSupportErrorIdentifier="";
    try
        [evidence.FFTSupport,probeAccounting]=sixgr.phy.srs.srsAntennaPowerFFTSupport( ...
            carrier,ofdm,timing,observation.StartSample,observation.EndSampleExclusive,support-1);
        evidence.FFTSupportAvailable=true;
        evidence.IsolatedFFTCapabilityProbeAccounting=probeAccounting;
    catch supportError
        evidence.FFTSupportErrorIdentifier=string(supportError.identifier);
    end
    token=string(jsonencode(evidence));
    out.SRS_RSRP_dBm=10*log10(reported)+30;
    out.SRSRSRPPerReceiveAntenna_dBm=10*log10(perBranchW)+30;
    out.SRSAbsolutePowerAvailable=true;
    out.SRSAbsolutePowerStatus="available_actual_antenna_capture_estimate_not_accuracy_qualified";
    if branchEvidence.Available
        out.SRSAbsolutePowerStatus="available_modeled_receiver_branch_power_not_accuracy_qualified";
    end
    out.SRSAbsolutePowerSource=evidence.Estimator;
    out.SRSAbsolutePowerReferencePlane=evidence.ReferencePlane;
    out.SRSAbsolutePowerAggregation=evidence.Aggregation;
    out.SRSAbsolutePowerBranchMean_dBm=10*log10(mean(perBranchW))+30;
    out.SRSAbsolutePowerSelectedBranch0=branch-1;
    out.SRSAbsolutePowerResourceID=resource.ResourceID;
    out.SRSAbsolutePowerEvidenceJSON=token;
    out.SRSAbsolutePowerEvidenceSHA256=string(sixgr.rrc.asn1.asn1SHA256Hex(unicode2native(char(token),'UTF-8')));
    if pathPolicy.Enabled
        try
            binding=struct('ReferencePlane',"internal_physical_receive_element_before_RX_front_end", ...
                'ResponseUnit',"sqrt_W",'SubcarrierSpacingHz',double(carrier.SubcarrierSpacing)*1000, ...
                'ObservationSHA256',observation.sampleHash(),'ReceivedGridSHA256',string(ofdm.GridSHA256), ...
                'TruthChannelConsumed',false,'PostRFEstimateConsumed',false, ...
                'OriginalAntennaPowerEvidenceSHA256',out.SRSAbsolutePowerEvidenceSHA256, ...
                'ObservationID',string(plane.ObservationID),'Resource',resource, ...
                'ObservationStartSample',observation.StartSample,'ObservationEndSampleExclusive',observation.EndSampleExclusive, ...
                'SampleRateHz',observation.SampleRateHz,'PhysicalConfigurationEpoch',epoch, ...
                'RawGridAmplitudeDivisor',scale,'Timing',timing,'Estimator',evidence.Estimator);
            result=sixgr.phy.srs.measureSRSDetectedPathPower(pathResponse/scale, ...
                [subcarrier symbol port]-1,pathNoise/(scale^2),pathPolicy,binding);
            fields=sixgr.phy.srs.srsPathPowerEvidence(result);
            for field=string(fieldnames(fields)).', out.(field)=fields.(field); end
        catch pathError
            out.SRSPathPowerStatus="unavailable_original_path_estimation_failed";
            out.SRSPathPowerErrorIdentifier=string(pathError.identifier);
        end
    end
catch cause
    % This independent measurement must not turn a usable practical SRS
    % receiver into a failure or leak a partly computed power value.
    out.SRSAbsolutePowerStatus="not_available_antenna_measurement_failed";
    out.SRSAbsolutePowerErrorIdentifier=string(cause.identifier);
end
end
