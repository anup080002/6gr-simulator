function [period, offset] = validateSRSPeriodOffset(period, offset)
%VALIDATESRSPERIODOFFSET Exact ordinary-SRS calendar, without rounding.
% TS 38.331 V18.8.0 6.3.2, SRS-PeriodicityAndOffset base IE. Positioning
% extensions accepted by newer Toolbox releases are not this profile.
allowed = [1 2 4 5 8 10 16 20 32 40 64 80 160 320 640 1280 2560];
assert(isnumeric(period) && ~islogical(period) && isreal(period) && ...
    isscalar(period) && isfinite(period) && any(period == allowed), ...
    'sixgr:phy:srs:InvalidPeriodicity', ...
    'Ordinary periodic SRS requires an explicitly configured base-IE slot period; no rounding or default period is allowed.');
assert(isnumeric(offset) && ~islogical(offset) && isreal(offset) && ...
    isscalar(offset) && isfinite(offset) && offset == fix(offset) && ...
    offset >= 0 && offset < period, ...
    'sixgr:phy:srs:InvalidPeriodOffset', ...
    'SRS period_offset must be an exact integer in [0,period_slots-1].');
period = double(period);
offset = double(offset);
end
