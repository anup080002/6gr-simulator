function T = deriveCyclicShiftSet(runId, configHash, prachCfg)
%DERIVECYCLICSHIFTSET Export configured preamble-to-cyclic-shift evidence.

ncs = sixgr.phy.prach.deriveNCSFromZeroCorrelationZone( ...
    prachCfg.ZeroCorrelationZone, prachCfg.RestrictedSet, prachCfg.ToolboxPRACH.LRA);
numPreambles = min(64, max(1, round(double(sixgr.util.structGet(prachCfg, "NumPreambles", 64)))));
preambles = 0:(numPreambles - 1);
lra = double(prachCfg.ToolboxPRACH.LRA);
rows = repmat(struct( ...
    "RunId", string(runId), ...
    "ConfigHash", string(configHash), ...
    "ZeroCorrelationZoneConfig", double(prachCfg.ZeroCorrelationZone), ...
    "RestrictedSet", string(prachCfg.RestrictedSet), ...
    "NCS", double(ncs), ...
    "CyclicShiftIndex", NaN, ...
    "CyclicShiftValue", NaN, ...
    "PreambleIndex", NaN, ...
    "Valid", true, ...
    "FailureReason", ""), numel(preambles), 1);
for ii = 1:numel(preambles)
    idx = double(preambles(ii));
    rows(ii).CyclicShiftIndex = idx;
    rows(ii).CyclicShiftValue = mod(idx * double(ncs), max(lra, 1));
    rows(ii).PreambleIndex = idx;
end
T = struct2table(rows, "AsArray", true);
end
