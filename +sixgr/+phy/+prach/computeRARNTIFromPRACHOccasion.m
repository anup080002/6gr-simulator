function [rarnti, coordinates] = computeRARNTIFromPRACHOccasion(occasion)
%COMPUTERARNTIFROMPRACHOCCASION Compute RA-RNTI for an NR PRACH occasion.

% Materialized occasions below use the resolver's explicit PRACH-clock
% s_id/t_id. The older fields here are accepted only for explicit-coordinate
% legacy callers without a PRACH object. Carrier symbols/slots cannot be
% treated as PRACH-clock coordinates when their numerologies differ.
symbol = double(sixgr.util.structGet(occasion, "CarrierStartSymbol", ...
    sixgr.util.structGet(occasion, "OccasionSymbol", ...
    sixgr.util.structGet(occasion, "SymbolLocation", 0))));
% TS 38.321 defines t_id as the index of the first PRACH-occasion slot
% within a system frame.  SlotIndex0 is the absolute carrier-slot index
% used by the campaign scheduler and can exceed 79 in later repetitions;
% it must not be substituted for the canonical PRACH-clock coordinates.
slot = double(sixgr.util.structGet(occasion, "Carrier.NSlot", ...
    sixgr.util.structGet(occasion, "SlotWithinFrame", ...
    sixgr.util.structGet(occasion, "SlotIndex0", ...
    sixgr.util.structGet(occasion, "OccasionSlot", 0)))));
freq = double(sixgr.util.structGet(occasion, "FrequencyIndex", ...
    sixgr.util.structGet(occasion, "OccasionFrequencyIndex", 0)));
ulCarrier = double(sixgr.util.structGet(occasion, "ULCarrierId", 0));
frame = double(sixgr.util.structGet(occasion, "Carrier.NFrame", ...
    sixgr.util.structGet(occasion, "OccasionFrame", 0)));
if all(isfield(occasion,{'RARNTISymbolIndex','RARNTISlotIndex'}))
    symbol=double(occasion.RARNTISymbolIndex);
    slot=double(occasion.RARNTISlotIndex);
elseif isfield(occasion,'PRACH')
    error('sixgr:phy:ra:IncompletePRACHOccasion', ...
        'A materialized PRACH occasion must carry its PRACH-clock RA-RNTI coordinates.');
end
coordinates = struct( ...
    "FrameNumber", frame, ...
    "SymbolIndex", symbol, ...
    "SlotIndex", slot, ...
    "FrequencyIndex", freq, ...
    "ULCarrierId", ulCarrier);
rarnti = sixgr.phy.ra.computeRARNTI( ...
    "SymbolIndex", symbol, ...
    "SlotIndex", slot, ...
    "FrequencyIndex", freq, ...
    "ULCarrierId", ulCarrier);
end
