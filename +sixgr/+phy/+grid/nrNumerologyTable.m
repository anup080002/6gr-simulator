function T = nrNumerologyTable(cyclicPrefix)
%NRNUMEROLOGYTABLE Compatibility table backed by NumerologyCatalog.
%
% Default output contains every normal-CP Release-18 generic numerology.
% Pass "extended" to obtain the sole extended-CP row (mu=2 / 60 kHz).

if nargin < 1 || strlength(string(cyclicPrefix)) == 0
    cyclicPrefix = "normal";
end
catalog = sixgr.phy.frame.NumerologyCatalog.table(cyclicPrefix);
T = table( ...
    catalog.Mu, ...
    catalog.SubcarrierSpacingKHz, ...
    catalog.SlotsPerSubframe, ...
    catalog.SlotsPerFrame, ...
    catalog.SymbolsPerSlot, ...
    catalog.SlotDurationSeconds, ...
    string(catalog.CyclicPrefix), ...
    'VariableNames', [ ...
        "mu", "scs_kHz", "slots_per_subframe", "slots_per_frame", ...
        "symbols_per_slot", "slot_duration_s", "cyclic_prefix"]);
end
