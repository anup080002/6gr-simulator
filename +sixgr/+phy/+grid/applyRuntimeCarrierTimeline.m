function [cfg, timeline] = applyRuntimeCarrierTimeline(cfg, absoluteSlotOneBased, frameOneBased)
%APPLYRUNTIMECARRIERTIMELINE Bind a runtime occasion to nrCarrierConfig time.
%
% Scenario/coupled-runtime slot numbers are one based.  nrCarrierConfig
% uses a zero-based slot within a zero-based system frame.  This function is
% the single conversion boundary used by both DL and UL waveform runners.

if nargin < 3
    frameOneBased = NaN;
end
absoluteSlotOneBased = double(absoluteSlotOneBased);
frameOneBased = double(frameOneBased);
if ~(isscalar(absoluteSlotOneBased) && isfinite(absoluteSlotOneBased) && ...
        absoluteSlotOneBased >= 1 && absoluteSlotOneBased == round(absoluteSlotOneBased))
    error("sixgr:grid:InvalidRuntimeAbsoluteSlot", ...
        "Runtime absolute slot must be a positive one-based integer.");
end

scsKHz = double(sixgr.util.structGet(cfg, ...
    "phy.carrier.SubcarrierSpacing", NaN));
if ~(isscalar(scsKHz) && isfinite(scsKHz) && scsKHz >= 15)
    error("sixgr:grid:MissingRuntimeNumerology", ...
        "Runtime carrier timing requires phy.carrier.SubcarrierSpacing.");
end
mu = log2(scsKHz / 15);
if abs(mu - round(mu)) > 1e-12 || mu < 0
    error("sixgr:grid:InvalidRuntimeNumerology", ...
        "Subcarrier spacing %.12g kHz is not an NR 15*2^mu numerology.", scsKHz);
end
mu = round(mu);
slotsPerFrame = 10 * 2^mu;
absoluteSlot0 = absoluteSlotOneBased - 1;
carrierSlot0 = mod(absoluteSlot0, slotsPerFrame);
carrierFrame0 = floor(absoluteSlot0 / slotsPerFrame);
expectedFrameOneBased = carrierFrame0 + 1;
if isfinite(frameOneBased) && (frameOneBased ~= round(frameOneBased) || ...
        frameOneBased < 1 || frameOneBased ~= expectedFrameOneBased)
    error("sixgr:grid:RuntimeFrameSlotMismatch", ...
        "Runtime frame/slot mismatch: absolute slot %d resolves to one-based frame %d, not %g.", ...
        absoluteSlotOneBased, expectedFrameOneBased, frameOneBased);
end

cfg = sixgr.util.structSet(cfg, "phy.carrier.NSlot", carrierSlot0);
cfg = sixgr.util.structSet(cfg, "phy.carrier.NFrame", carrierFrame0);
cfg = sixgr.util.structSet(cfg, ...
    "lls6g.runtime.AbsoluteSlotIndex0", absoluteSlot0);
cfg = sixgr.util.structSet(cfg, ...
    "lls6g.runtime.AbsoluteSlotIndexOneBased", absoluteSlotOneBased);
cfg = sixgr.util.structSet(cfg, ...
    "lls6g.runtime.CarrierSlotIndex0", carrierSlot0);
cfg = sixgr.util.structSet(cfg, ...
    "lls6g.runtime.CarrierFrameIndex0", carrierFrame0);

timeline = struct( ...
    "AbsoluteSlotIndex0", absoluteSlot0, ...
    "AbsoluteSlotIndexOneBased", absoluteSlotOneBased, ...
    "CarrierSlotIndex0", carrierSlot0, ...
    "CarrierFrameIndex0", carrierFrame0, ...
    "FrameIndexOneBased", expectedFrameOneBased, ...
    "SlotsPerFrame", slotsPerFrame, ...
    "Numerology", mu, ...
    "Source", "coupled_runtime_absolute_slot_to_nrCarrierConfig");
end
