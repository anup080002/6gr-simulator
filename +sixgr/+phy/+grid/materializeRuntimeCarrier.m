function [carrier, evidence] = materializeRuntimeCarrier(cfg, frozenCarrier, direction)
%MATERIALIZERUNTIMECARRIER Build the carrier for the current runtime occasion.
%
% A frozen scheduler grant owns immutable carrier geometry, but it does not
% own the current NR frame/slot. Reusing its CarrierConfig after the runtime
% advances silently moves the waveform back to the grant-freeze occasion.

if nargin < 2
    frozenCarrier = [];
end
if nargin < 3
    direction = "";
end
direction = upper(strtrim(string(direction)));

[carrier, info] = sixgr.phy.grid.makeCarrier(cfg);
absoluteSlot0 = double(sixgr.util.structGet(cfg, ...
    "lls6g.runtime.AbsoluteSlotIndex0", NaN));
carrierSlot0 = double(sixgr.util.structGet(cfg, ...
    "lls6g.runtime.CarrierSlotIndex0", NaN));
carrierFrame0 = double(sixgr.util.structGet(cfg, ...
    "lls6g.runtime.CarrierFrameIndex0", NaN));
if ~(isscalar(absoluteSlot0) && isfinite(absoluteSlot0) && ...
        absoluteSlot0 >= 0 && absoluteSlot0 == fix(absoluteSlot0))
    error("sixgr:grid:MissingRuntimeCarrierTimeline", ...
        "%s waveform replay requires an explicit absolute runtime slot.", ...
        char(direction));
end
if ~(isscalar(carrierSlot0) && isfinite(carrierSlot0) && ...
        carrierSlot0 == fix(carrierSlot0) && carrierSlot0 >= 0 && ...
        double(carrier.NSlot) == carrierSlot0)
    error("sixgr:grid:RuntimeCarrierSlotMismatch", ...
        "%s runtime carrier slot is %g; the live timeline requires %g.", ...
        char(direction), double(carrier.NSlot), carrierSlot0);
end
if ~(isscalar(carrierFrame0) && isfinite(carrierFrame0) && ...
        carrierFrame0 == fix(carrierFrame0) && carrierFrame0 >= 0 && ...
        double(carrier.NFrame) == carrierFrame0)
    error("sixgr:grid:RuntimeCarrierFrameMismatch", ...
        "%s runtime carrier frame is %g; the live timeline requires %g.", ...
        char(direction), double(carrier.NFrame), carrierFrame0);
end

validatedFrozenCarrier = ~isempty(frozenCarrier);
if validatedFrozenCarrier
    localAssertImmutableCarrierField(carrier, frozenCarrier, ...
        "NCellID", direction, false);
    localAssertImmutableCarrierField(carrier, frozenCarrier, ...
        "SubcarrierSpacing", direction, false);
    localAssertImmutableCarrierField(carrier, frozenCarrier, ...
        "NSizeGrid", direction, false);
    localAssertImmutableCarrierField(carrier, frozenCarrier, ...
        "NStartGrid", direction, false);
    localAssertImmutableCarrierField(carrier, frozenCarrier, ...
        "CyclicPrefix", direction, true);
end

evidence = struct( ...
    "Direction", direction, ...
    "AbsoluteSlotIndex0", absoluteSlot0, ...
    "CarrierSlotIndex0", double(carrier.NSlot), ...
    "CarrierFrameIndex0", double(carrier.NFrame), ...
    "FrozenCarrierGeometryValidated", validatedFrozenCarrier, ...
    "CarrierGeometrySource", "frozen_grant_validated_against_live_config", ...
    "CarrierTimelineSource", "coupled_runtime_absolute_slot", ...
    "CarrierInfo", info);
end

function localAssertImmutableCarrierField(runtimeCarrier, frozenCarrier, ...
        fieldName, direction, compareAsString)
try
    runtimeValue = runtimeCarrier.(fieldName);
    frozenValue = frozenCarrier.(fieldName);
catch ME
    error("sixgr:grid:InvalidFrozenCarrierContract", ...
        "%s frozen carrier is missing immutable field %s (%s).", ...
        char(direction), fieldName, ME.message);
end
if compareAsString
    matches = strcmpi(strtrim(string(runtimeValue)), ...
        strtrim(string(frozenValue)));
else
    matches = isequal(double(runtimeValue), double(frozenValue));
end
if ~matches
    error("sixgr:grid:FrozenCarrierGeometryMismatch", ...
        "%s frozen/runtime carrier field %s differs (frozen=%s, runtime=%s).", ...
        char(direction), fieldName, char(string(frozenValue)), ...
        char(string(runtimeValue)));
end
end
