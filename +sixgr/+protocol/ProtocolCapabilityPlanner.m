classdef ProtocolCapabilityPlanner
    %PROTOCOLCAPABILITYPLANNER Resolve enabled tuples before state mutation.

    methods (Static)
        function plan = resolve(profileID, feature, vectorRoot)
            arguments
                profileID (1,1) string
                feature (1,1) string
                vectorRoot (1,1) string
            end
            matrixPath = fullfile(vectorRoot, ...
                "protocol_capability_profile_matrix.csv");
            if ~isfile(matrixPath)
                error("sixgr:protocol:UnsupportedCapability", ...
                    "Protocol capability matrix is unavailable.");
            end
            rows = readtable(matrixPath, "TextType", "string", ...
                "VariableNamingRule", "preserve");
            match = rows.ProfileID == profileID & rows.Feature == feature;
            if sum(match) ~= 1
                error("sixgr:protocol:UnsupportedCapability", ...
                    "Capability tuple %s/%s is not declared.", ...
                    profileID, feature);
            end
            row = rows(match,:);
            declared = sixgr.protocol.ProtocolCapabilityPlanner.truth( ...
                row.Supported);
            oracleReady = true;
            reason = string(row.Reason);
            if sixgr.protocol.ProtocolCapabilityPlanner.requiresRRCOracle(feature)
                oracleReady = ...
                    sixgr.protocol.ProtocolCapabilityPlanner.rrcOracleReady( ...
                    vectorRoot);
                if declared && ~oracleReady
                    reason = "independent Release-18 UPER vector required before enable";
                end
            end
            supported = declared && oracleReady;
            plan = struct( ...
                "CaseID", string(row.CaseID), ...
                "ProfileID", profileID, ...
                "Feature", feature, ...
                "DeclaredSupported", declared, ...
                "IndependentOracleReady", oracleReady, ...
                "Supported", supported, ...
                "PlanningResult", string( ...
                    sixgr.protocol.ProtocolCapabilityPlanner.select(supported, ...
                    "EXECUTE", "REJECT")), ...
                "PlanningRejected", ~supported, ...
                "StateChanged", false, ...
                "Reason", reason);
        end

        function plan = require(profileID, feature, vectorRoot)
            plan = sixgr.protocol.ProtocolCapabilityPlanner.resolve( ...
                profileID, feature, vectorRoot);
            if ~plan.Supported
                error("sixgr:protocol:UnsupportedCapability", ...
                    "Capability %s/%s rejected before execution: %s.", ...
                    profileID, feature, plan.Reason);
            end
        end

        function ready = rrcOracleReady(vectorRoot)
            catalogPath = fullfile(vectorRoot, ...
                "protocol_rrc_message_vectors.csv");
            frozenPath = fullfile(vectorRoot, ...
                "protocol_rrc_release18_uper_vectors.csv");
            if ~isfile(catalogPath) || ~isfile(frozenPath) || ...
                    ~sixgr.l3.rrc18.asn1.RRCBoundedUPERCodec.available()
                ready = false;
                return;
            end
            catalog = sixgr.protocol.ProtocolCapabilityPlanner.readStrings( ...
                catalogPath);
            frozen = sixgr.protocol.ProtocolCapabilityPlanner.readStrings( ...
                frozenPath);
            positive = catalog( ...
                sixgr.protocol.ProtocolCapabilityPlanner.truth( ...
                catalog.ExpectedValid),:);
            keys = positive.CaseID + "|" + positive.MessageType + "|" + ...
                positive.TransactionID;
            frozenKeys = frozen.CaseID + "|" + frozen.MessageType + "|" + ...
                frozen.TransactionID;
            ready = ~isempty(keys) && all(ismember(keys, frozenKeys));
        end
    end

    methods (Static, Access = private)
        function value = requiresRRCOracle(feature)
            value = startsWith(feature, "RRC_") || ...
                feature == "INTRA_FREQ_HO";
        end

        function value = truth(input)
            value = ismember(lower(strtrim(string(input))), ...
                ["1","true","yes","pass"]);
        end

        function value = select(condition, ifTrue, ifFalse)
            if condition
                value = ifTrue;
            else
                value = ifFalse;
            end
        end

        function value = readStrings(path)
            options = detectImportOptions(path, "Delimiter", ",", ...
                "VariableNamingRule", "preserve");
            options = setvartype(options, options.VariableNames, "string");
            value = readtable(path, options);
        end
    end
end
