classdef ProtocolVectorValidator
    %PROTOCOLVECTORVALIDATOR Replay independent bounded protocol floors.

    methods (Static)
        function result = validate(vectorRoot)
            arguments
                vectorRoot (1,1) string
            end
            families = { ...
                "rlc_um_header", "protocol_rlc_um_header_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.rlcUM; ...
                "rlc_am_header", "protocol_rlc_am_header_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.rlcAM; ...
                "rlc_status", "protocol_rlc_status_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.rlcStatus; ...
                "rlc_state", "protocol_rlc_timer_state_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.rlcState; ...
                "pdcp_header", "protocol_pdcp_header_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.pdcpHeader; ...
                "pdcp_count", "protocol_pdcp_count_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.pdcpCount; ...
                "pdcp_security", "protocol_pdcp_security_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.pdcpSecurity; ...
                "pdcp_reordering", "protocol_pdcp_reordering_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.pdcpReordering; ...
                "sdap_header", "protocol_sdap_header_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.sdapHeader; ...
                "sdap_mapping", "protocol_sdap_mapping_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.sdapMapping; ...
                "rrc_semantics", "protocol_rrc_message_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.rrcSemantics; ...
                "rrc_uper", "protocol_rrc_release18_uper_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.rrcUPER; ...
                "bearer_config", "protocol_radio_bearer_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.bearerConfig; ...
                "handover", "protocol_handover_state_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.stateTable; ...
                "traffic", "protocol_traffic_arrival_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.traffic; ...
                "lineage", "protocol_lineage_vectors.csv", ...
                    @sixgr.protocol.ProtocolVectorValidator.lineage};
            n = size(families, 1);
            details = table('Size',[n 9], ...
                'VariableTypes',repmat({'string'},1,9), ...
                'VariableNames',{'VectorFamily','FileName','OracleClass', ...
                'OracleImplementation','OracleVersion','OracleArtifactSHA256', ...
                'Cases','MismatchCount','MaxAbsoluteError'});
            totalCases = 0;
            totalMismatch = 0;
            for index = 1:n
                fileName = string(families{index,2});
                path = fullfile(vectorRoot, fileName);
                rows = sixgr.protocol.ProtocolVectorValidator.read(path);
                [mismatch, maxError] = families{index,3}(rows, vectorRoot);
                cases = height(rows);
                totalCases = totalCases + cases;
                totalMismatch = totalMismatch + mismatch;
                oracleClass = "independent_frozen_vector";
                if string(families{index,1}) == "rrc_semantics"
                    oracleClass = "independent_enablement_guard";
                end
                details(index,:) = {string(families{index,1}), fileName, ...
                    oracleClass, "external_protocol_pack", ...
                    "manifest_v1", sixgr.protocol.ProtocolHash.file(path), ...
                    string(cases), string(mismatch), string(maxError)};
            end
            result = struct("Passed", totalMismatch == 0, ...
                "Cases", totalCases, "MismatchCount", totalMismatch, ...
                "Details", details);
        end
    end

    methods (Static, Access = private)
        function [mismatch, maxError] = rlcUM(rows, ~)
            mismatch = 0;
            for index = 1:height(rows)
                valid = sixgr.protocol.ProtocolVectorValidator.truth( ...
                    rows.ExpectedValid(index));
                try
                    bytes = sixgr.l2.rlc18.RLCHeaderCodec.encodeUM( ...
                        str2double(rows.SNBits(index)), ...
                        str2double(rows.SI(index)), ...
                        sixgr.protocol.ProtocolVectorValidator.number( ...
                        rows.SN(index)), ...
                        sixgr.protocol.ProtocolVectorValidator.number( ...
                        rows.SO(index)));
                    actualValid = true;
                    actualHex = sixgr.l2.rlc18.RLCHeaderCodec.hex(bytes);
                catch
                    actualValid = false;
                    actualHex = "";
                end
                mismatch = mismatch + double(actualValid ~= valid || ...
                    (valid && actualHex ~= upper(rows.HeaderHex(index))));
            end
            maxError = mismatch > 0;
        end

