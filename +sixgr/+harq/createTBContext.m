function ctx = createTBContext(meta)
%CREATETBCONTEXT Canonicalize the coding context owned by one HARQ TB.
% Keep this file ASCII-only.

if nargin < 1 || ~isstruct(meta)
    error("sixgr:harq:BadTBContextMeta", ...
        "createTBContext requires a meta struct.");
end

previous = localContextStruct(sixgr.util.structGet(meta, "PreviousContext", ...
    sixgr.util.structGet(meta, "TransportBlockContext", struct())));
grant = sixgr.util.structGet(meta, "Grant", struct());
phyGrant = sixgr.util.structGet(meta, "PHYGrant", sixgr.util.structGet(grant, "PHYGrant", struct()));
layout = localResolveCodingLayout(meta, grant, phyGrant);
direction = upper(string(localFirstNonEmpty( ...
    sixgr.util.structGet(meta, "Direction", ""), ...
    sixgr.util.structGet(grant, "Direction", ""), ...
    sixgr.util.structGet(phyGrant, "Direction", ""), ...
    sixgr.util.structGet(previous, "Direction", ""))));
if ~(direction == "DL" || direction == "UL")
    error("sixgr:harq:BadTBContextDirection", ...
        "HARQ TB context direction must be DL or UL.");
end
if ~localShouldCarryPreviousContext(meta, grant, phyGrant, previous)
    previous = struct();
end

prbSet = localNumericRow(localFirstNonEmpty( ...
    sixgr.util.structGet(meta, "PRBSet", []), ...
    sixgr.util.structGet(grant, "PRBSet", []), ...
    sixgr.util.structGet(phyGrant, "ResourceAllocation.PRBSet", []), ...
    sixgr.util.structGet(previous, "OriginalPRBSet", [])));
symbolAllocation = localNumericRow(localFirstNonEmpty( ...
    sixgr.util.structGet(meta, "SymbolAllocation", []), ...
    sixgr.util.structGet(grant, "SymbolAllocation", []), ...
    sixgr.util.structGet(phyGrant, "ResourceAllocation.SymbolAllocation", []), ...
    sixgr.util.structGet(previous, "OriginalSymbolAllocation", [])));
rateMatchedTotal = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "RateMatchedBitsTotal", NaN), ...
    sixgr.util.structGet(meta, "CurrentRateMatchedBitsTotal", NaN), ...
    sixgr.util.structGet(layout, "RateMatchedBitCount", NaN), ...
    sixgr.util.structGet(grant, "CodedBitCountG", NaN), ...
    sixgr.util.structGet(grant, "RateMatchedBits", NaN), ...
    sixgr.util.structGet(previous, "CurrentRateMatchedBitsTotal", NaN), ...
    sixgr.util.structGet(previous, "OriginalRateMatchedBitsTotal", NaN));
rateMatchedPerCB = localNumericRow(localFirstNonEmpty( ...
    sixgr.util.structGet(meta, "RateMatchedBitsPerCB", []), ...
    sixgr.util.structGet(meta, "CurrentRateMatchedBitsPerCB", []), ...
    sixgr.util.structGet(layout, "E_r", []), ...
    sixgr.util.structGet(previous, "CurrentRateMatchedBitsPerCB", []), ...
    sixgr.util.structGet(previous, "OriginalRateMatchedBitsPerCB", [])));
tbsBits = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "TBSBits", NaN), ...
    sixgr.util.structGet(grant, "TBSBits", NaN), ...
    sixgr.util.structGet(grant, "TransportBlockSize", NaN), ...
    sixgr.util.structGet(layout, "TBSBits", NaN), ...
    sixgr.util.structGet(previous, "TBSBits", NaN));
if ~(isfinite(tbsBits) && tbsBits > 0)
    error("sixgr:harq:BadTBContextTBS", ...
        "HARQ TB context requires a positive TBSBits value.");
end

modulation = string(localFirstNonEmpty( ...
    sixgr.util.structGet(meta, "Modulation", ""), ...
    sixgr.util.structGet(grant, "Modulation", ""), ...
    sixgr.util.structGet(layout, "Modulation", ""), ...
    sixgr.util.structGet(previous, "OriginalModulation", "")));
targetCodeRate = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "TargetCodeRate", NaN), ...
    sixgr.util.structGet(grant, "TargetCodeRate", NaN), ...
    sixgr.util.structGet(layout, "TargetCodeRate", NaN), ...
    sixgr.util.structGet(phyGrant, "CodingLayout.TargetCodeRate", NaN), ...
    sixgr.util.structGet(previous, "OriginalTargetCodeRate", NaN));
numLayers = localPositiveInteger(localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "NumLayers", NaN), ...
    sixgr.util.structGet(grant, "NumLayers", NaN), ...
    sixgr.util.structGet(grant, "Layers", NaN), ...
    sixgr.util.structGet(layout, "NumLayers", NaN), ...
    sixgr.util.structGet(previous, "OriginalNumLayers", NaN)), 1);
rank = localPositiveInteger(localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "Rank", NaN), ...
    sixgr.util.structGet(grant, "Rank", NaN), ...
    sixgr.util.structGet(grant, "RI", NaN), ...
    sixgr.util.structGet(previous, "OriginalRank", NaN), numLayers), numLayers);

frozenPhyGrant = localFirstStruct( ...
    sixgr.util.structGet(meta, "FrozenPHYGrant", struct()), ...
    sixgr.util.structGet(previous, "FrozenPHYGrant", struct()), ...
    phyGrant, ...
    sixgr.util.structGet(grant, "PHYGrant", struct()));
frozenCfg = localFirstNonEmpty( ...
    sixgr.util.structGet(meta, "FrozenPDSCHorPUSCHConfig", []), ...
    sixgr.util.structGet(previous, "FrozenPDSCHorPUSCHConfig", []), ...
    localFrozenDirectionalConfig(direction, grant), []);
codeBlockLayoutHash = string(sixgr.harq.hashCodeBlockLayout(layout));

ctx = struct();
ctx.ContractVersion = "HARQTransportBlockContext/v1";
ctx.Direction = char(direction);
ctx.CellId = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "CellId", NaN), ...
    sixgr.util.structGet(grant, "ServingCell", NaN), ...
    sixgr.util.structGet(grant, "BaseStationID", NaN), ...
    sixgr.util.structGet(phyGrant, "ChannelStateKey.ServingCell", NaN), ...
    sixgr.util.structGet(previous, "CellId", NaN));
ctx.UeId = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "UeId", NaN), ...
    sixgr.util.structGet(grant, "UEIndex", NaN), ...
    sixgr.util.structGet(grant, "UEID", NaN), ...
    sixgr.util.structGet(phyGrant, "ChannelStateKey.UEIndex", NaN), ...
    sixgr.util.structGet(previous, "UeId", NaN));
ctx.RNTI = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "RNTI", NaN), ...
    sixgr.util.structGet(grant, "RNTI", NaN), ...
    sixgr.util.structGet(phyGrant, "HARQProcessKey.RNTI", NaN), ...
    sixgr.util.structGet(previous, "RNTI", NaN));
ctx.HARQProcessId = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "HARQProcessId", NaN), ...
    sixgr.util.structGet(meta, "HarqID", NaN), ...
    sixgr.util.structGet(grant, "HARQ.HARQProcess", NaN), ...
    sixgr.util.structGet(grant, "HARQ.HarqID", NaN), ...
    sixgr.util.structGet(grant, "HARQProcessId", NaN), ...
    sixgr.util.structGet(phyGrant, "HARQProcessKey.HARQProcess", NaN), ...
    sixgr.util.structGet(previous, "HARQProcessId", NaN));
ctx.NDIEpoch = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "NDIEpoch", NaN), ...
    sixgr.util.structGet(grant, "HARQ.NDIEpoch", NaN), ...
    sixgr.util.structGet(grant, "NDIEpoch", NaN), ...
    sixgr.util.structGet(previous, "NDIEpoch", NaN));
ctx.NDI = logical(localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "NDI", NaN), ...
    sixgr.util.structGet(grant, "HARQ.NDI", NaN), ...
    sixgr.util.structGet(grant, "NDI", NaN), ...
    sixgr.util.structGet(phyGrant, "HARQProcessKey.NDI", NaN), ...
    sixgr.util.structGet(previous, "NDI", NaN), 1));
ctx.TBId = char(string(localFirstNonEmpty( ...
    sixgr.util.structGet(meta, "TBId", ""), ...
    sixgr.util.structGet(grant, "TransportBlockId", ""), ...
    sixgr.util.structGet(grant, "TBIdentity", ""), ...
    sixgr.util.structGet(grant, "TBId", ""), ...
    sixgr.util.structGet(previous, "TBId", ""))));
ctx.CodewordId = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "CodewordId", NaN), ...
    sixgr.util.structGet(grant, "Codeword", NaN), ...
    sixgr.util.structGet(grant, "CodewordIndex", NaN), ...
    sixgr.util.structGet(previous, "CodewordId", NaN), 0);
ctx.FirstTxCanonicalSlot = localFirstFiniteScalar( ...
    sixgr.util.structGet(previous, "FirstTxCanonicalSlot", NaN), ...
    sixgr.util.structGet(meta, "FirstTxCanonicalSlot", NaN), ...
    sixgr.util.structGet(grant, "Slot", NaN));
ctx.OriginalGrantId = char(string(localFirstNonEmpty( ...
    sixgr.util.structGet(previous, "OriginalGrantId", ""), ...
    sixgr.util.structGet(meta, "OriginalGrantId", ""), ...
    sixgr.util.structGet(grant, "GrantContextId", ""), ...
    sixgr.util.structGet(phyGrant, "GrantContextId", ""))));
ctx.OriginalMCS = localFirstFiniteScalar( ...
    sixgr.util.structGet(previous, "OriginalMCS", NaN), ...
    sixgr.util.structGet(meta, "OriginalMCS", NaN), ...
    sixgr.util.structGet(grant, "MCSIndex", NaN), ...
    sixgr.util.structGet(grant, "MCS", NaN), ...
    sixgr.util.structGet(phyGrant, "CodingLayout.MCSIndex", NaN));
ctx.OriginalModulation = char(localCarryForwardString(previous, "OriginalModulation", modulation));
ctx.OriginalQm = localQm(ctx.OriginalModulation);
ctx.OriginalTargetCodeRate = localFirstFiniteScalar( ...
    sixgr.util.structGet(previous, "OriginalTargetCodeRate", NaN), targetCodeRate);
ctx.OriginalRank = localFirstFiniteScalar(sixgr.util.structGet(previous, "OriginalRank", NaN), rank);
ctx.OriginalNumLayers = localFirstFiniteScalar(sixgr.util.structGet(previous, "OriginalNumLayers", NaN), numLayers);
ctx.OriginalPRBSet = localCarryForwardNumeric(previous, "OriginalPRBSet", prbSet);
ctx.OriginalSymbolAllocation = localCarryForwardNumeric(previous, "OriginalSymbolAllocation", symbolAllocation);
ctx.OriginalMappingType = char(string(localFirstNonEmpty( ...
    sixgr.util.structGet(previous, "OriginalMappingType", ""), ...
    sixgr.util.structGet(meta, "MappingType", ""), ...
    sixgr.util.structGet(grant, "MappingType", ""))));
ctx.OriginalNRE = localFirstFiniteScalar( ...
    sixgr.util.structGet(previous, "OriginalNRE", NaN), ...
    sixgr.util.structGet(meta, "NRE", NaN), ...
    sixgr.util.structGet(grant, "LayerDataRE", NaN), ...
    sixgr.util.structGet(grant, "DataRECountPerLayer", NaN), ...
    localNREFromGrant(grant, prbSet));
ctx.OriginalRateMatchedBitsTotal = localFirstFiniteScalar( ...
    sixgr.util.structGet(previous, "OriginalRateMatchedBitsTotal", NaN), rateMatchedTotal);
ctx.OriginalRateMatchedBitsPerCB = localCarryForwardNumeric(previous, "OriginalRateMatchedBitsPerCB", rateMatchedPerCB);
ctx.TBSBits = double(localFirstFiniteScalar( ...
    sixgr.util.structGet(previous, "TBSBits", NaN), tbsBits));
ctx.TBCRCType = char(string(localFirstNonEmpty( ...
    sixgr.util.structGet(previous, "TBCRCType", ""), ...
    sixgr.util.structGet(layout, "TBCRCType", ""))));
ctx.LDPCBaseGraph = localFirstFiniteScalar( ...
    sixgr.util.structGet(previous, "LDPCBaseGraph", NaN), ...
    sixgr.util.structGet(layout, "BaseGraph", NaN), ...
    sixgr.util.structGet(layout, "BGN", NaN));
ctx.LiftingSizeZc = localFirstFiniteScalar( ...
    sixgr.util.structGet(previous, "LiftingSizeZc", NaN), ...
    sixgr.util.structGet(layout, "LiftingSize", NaN), ...
    sixgr.util.structGet(layout, "Zc", NaN));
ctx.NumCodeBlocks = localPositiveInteger(localFirstFiniteScalar( ...
    sixgr.util.structGet(previous, "NumCodeBlocks", NaN), ...
    sixgr.util.structGet(layout, "NumCodeBlocks", NaN), ...
    sixgr.util.structGet(layout, "C", NaN)), 1);
ctx.CodeBlockSizes = localCarryForwardNumeric(previous, "CodeBlockSizes", localCodeBlockSizes(layout));
ctx.FillerBits = localCarryForwardNumeric(previous, "FillerBits", localFillerBits(layout));
ctx.NcbPerCodeBlock = localCarryForwardNumeric(previous, "NcbPerCodeBlock", localNcbPerCodeBlock(layout));
ctx.CodeBlockLayoutHash = char(codeBlockLayoutHash);
ctx.FrozenPHYGrant = frozenPhyGrant;
ctx.FrozenPDSCHorPUSCHConfig = frozenCfg;
ctx.DMRSConfigHash = char(localCarryForwardString(previous, "DMRSConfigHash", localAspectHash(frozenCfg, "dmrs")));
ctx.PTRSConfigHash = char(localCarryForwardString(previous, "PTRSConfigHash", localAspectHash(frozenCfg, "ptrs")));
ctx.CurrentRateMatchedBitsTotal = double(rateMatchedTotal);
ctx.CurrentRateMatchedBitsPerCB = double(rateMatchedPerCB(:).');
ctx.LastObservedRV = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "RV", NaN), ...
    sixgr.util.structGet(grant, "HARQ.RV", NaN), ...
    sixgr.util.structGet(grant, "RV", NaN), ...
    sixgr.util.structGet(phyGrant, "HARQProcessKey.RV", NaN), ...
    sixgr.util.structGet(previous, "LastObservedRV", NaN));
ctx.RVSequence = localNumericRow(localFirstNonEmpty( ...
    sixgr.util.structGet(meta, "RVSequence", []), ...
    sixgr.util.structGet(previous, "RVSequence", [])));
ctx.EffectiveInitialCodeRate = localSafeRatio(ctx.TBSBits, ctx.OriginalRateMatchedBitsTotal);
ctx.EffectiveCurrentTxCodeRate = localSafeRatio(ctx.TBSBits, ctx.CurrentRateMatchedBitsTotal);
ctx.ShortIRRetx = logical(sixgr.util.structGet(previous, "ShortIRRetx", false));
ctx.HARQContextHash = char(localContextHash(ctx));
end

function layout = localResolveCodingLayout(meta, grant, phyGrant)
layout = sixgr.util.structGet(meta, "CodingLayout", struct());
if iscell(layout)
    layout = localCellOrDefault(layout, 1, struct());
end
if ~(isstruct(layout) && ~isempty(fieldnames(layout)))
    layout = sixgr.util.structGet(meta, "CodingLayouts", struct());
    if iscell(layout)
        layout = localCellOrDefault(layout, 1, struct());
    end
end
if ~(isstruct(layout) && ~isempty(fieldnames(layout)))
    layout = sixgr.util.structGet(phyGrant, "CodingLayout", struct());
end
if ~(isstruct(layout) && ~isempty(fieldnames(layout)))
    layout = sixgr.util.structGet(grant, "CodingLayout", struct());
end
if ~(isstruct(layout) && ~isempty(fieldnames(layout)))
    error("sixgr:harq:MissingCodingLayout", ...
        "HARQ TB context creation requires a coding layout.");
end
end

function value = localCellOrDefault(cellValue, idx, fallback)
value = fallback;
if iscell(cellValue) && numel(cellValue) >= idx && ~isempty(cellValue{idx})
    value = cellValue{idx};
end
end

function cfg = localFrozenDirectionalConfig(direction, grant)
cfg = [];
if upper(string(direction)) == "UL"
    cfg = sixgr.util.structGet(grant, "PUSCHConfig", []);
else
    cfg = sixgr.util.structGet(grant, "PDSCHConfig", []);
end
end

function hash = localAspectHash(value, token)
hash = "";
payload = localAspectPayload(value, lower(string(token)));
if isempty(payload)
    return;
end
hash = string(sixgr.util.sha256Hex(localCanonicalBytes(payload)));
end

function payload = localAspectPayload(value, token)
payload = [];
if isempty(value)
    return;
end
if isobject(value)
    payload = struct("Class", class(value), "Summary", localHashFriendlyValue(value));
    return;
end
if isstruct(value)
    names = string(fieldnames(value));
    keep = contains(lower(names), token);
    if any(keep)
        payload = struct();
        keepNames = names(keep);
        for i = 1:numel(keepNames)
            payload.(char(keepNames(i))) = localHashFriendlyValue(value.(char(keepNames(i))));
        end
        payload = orderfields(payload);
        return;
    end
    payload = struct("Class", class(value), "Summary", localHashFriendlyValue(value));
    return;
end
payload = struct("Class", class(value), "Summary", localHashFriendlyValue(value));
end

function value = localHashFriendlyValue(value)
if isempty(value) || isnumeric(value) || islogical(value) || ischar(value) || isstring(value)
    return;
end
if iscell(value)
    value = cellfun(@localHashFriendlyValue, value, "UniformOutput", false);
    return;
end
if isobject(value)
    try
        displayText = strtrim(string(evalc("disp(value)")));
        if numel(displayText) > 1
            displayText = displayText(1);
        end
        value = struct("Class", class(value), "Display", char(displayText));
    catch
        value = struct("Class", class(value), "Display", class(value));
    end
    return;
end
if isstruct(value)
    names = sort(string(fieldnames(value)));
    out = struct();
    for i = 1:numel(names)
        out.(char(names(i))) = localHashFriendlyValue(value.(char(names(i))));
    end
    value = out;
    return;
end
value = char(string(value));
end

function bytes = localCanonicalBytes(value)
try
    bytes = uint8(unicode2native(char(jsonencode(localHashFriendlyValue(value))), "UTF-8"));
catch
    bytes = uint8(unicode2native(char(string(value)), "UTF-8"));
end
end

function ctx = localContextStruct(value)
if isstruct(value)
    ctx = value;
else
    ctx = struct();
end
end

function value = localFirstStruct(varargin)
value = struct();
for i = 1:nargin
    raw = varargin{i};
    if isstruct(raw) && ~isempty(fieldnames(raw))
        value = raw;
        return;
    end
end
end

function value = localFirstNonEmpty(varargin)
value = [];
for i = 1:nargin
    raw = varargin{i};
    if isstring(raw)
        if any(strlength(strtrim(raw)) > 0)
            value = raw;
            return;
        end
    elseif ischar(raw)
        if strlength(strtrim(string(raw))) > 0
            value = raw;
            return;
        end
    elseif isnumeric(raw) || islogical(raw)
        if ~isempty(raw)
            value = raw;
            return;
        end
    elseif iscell(raw)
        if ~isempty(raw)
            value = raw;
            return;
        end
    elseif isobject(raw) || isstruct(raw)
        if ~isempty(raw)
            value = raw;
            return;
        end
    end
end
end

function value = localFirstFiniteScalar(varargin)
value = NaN;
for i = 1:nargin
    raw = varargin{i};
    if isempty(raw)
        continue;
    end
    if islogical(raw)
        raw = double(raw);
    elseif ~isnumeric(raw)
        continue;
    end
    raw = double(raw(:));
    raw = raw(isfinite(raw));
    if ~isempty(raw)
        value = raw(1);
        return;
    end
end
end

function tf = localFirstLogical(varargin)
tf = false;
for i = 1:nargin
    raw = varargin{i};
    if isempty(raw)
        continue;
    end
    if islogical(raw)
        tf = logical(raw(1));
        return;
    end
    if isnumeric(raw)
        raw = double(raw(:));
        raw = raw(isfinite(raw));
        if ~isempty(raw)
            tf = logical(raw(1));
            return;
        end
    end
end
end

function tf = localShouldCarryPreviousContext(meta, grant, phyGrant, previous)
tf = false;
if ~(isstruct(previous) && ~isempty(fieldnames(previous)))
    return;
end
isRetx = localFirstLogical( ...
    sixgr.util.structGet(meta, "IsRetransmission", []), ...
    sixgr.util.structGet(grant, "IsRetransmission", []), ...
    sixgr.util.structGet(grant, "HARQ.IsRetransmission", []), ...
    sixgr.util.structGet(phyGrant, "HARQProcessKey.IsRetransmission", []), ...
    false);
if ~isRetx
    return;
end
previousNDI = localFirstFiniteScalar(sixgr.util.structGet(previous, "NDI", NaN));
currentNDI = localFirstFiniteScalar( ...
    sixgr.util.structGet(meta, "NDI", NaN), ...
    sixgr.util.structGet(grant, "HARQ.NDI", NaN), ...
    sixgr.util.structGet(grant, "NDI", NaN), ...
    sixgr.util.structGet(phyGrant, "HARQProcessKey.NDI", NaN));
if isfinite(previousNDI) && isfinite(currentNDI) && logical(previousNDI) ~= logical(currentNDI)
    return;
end
tf = true;
end

function value = localPositiveInteger(raw, fallback)
value = localFirstFiniteScalar(raw, fallback);
if ~(isfinite(value) && value >= 1)
    value = fallback;
end
value = max(1, round(double(value)));
end

function row = localNumericRow(raw)
if isempty(raw)
    row = zeros(1, 0);
    return;
end
row = double(raw(:).');
row = row(isfinite(row));
end

function value = localCarryForwardNumeric(previous, fieldName, fallback)
value = localNumericRow(sixgr.util.structGet(previous, fieldName, fallback));
if isempty(value)
    value = localNumericRow(fallback);
end
end

function value = localCarryForwardString(previous, fieldName, fallback)
value = string(sixgr.util.structGet(previous, fieldName, ""));
value = strtrim(value);
if strlength(value) < 1
    value = string(fallback);
end
end

function q = localQm(modulation)
token = upper(strtrim(char(string(modulation))));
switch token
    case "QPSK"
        q = 2;
    case "16QAM"
        q = 4;
    case "64QAM"
        q = 6;
    case "256QAM"
        q = 8;
    case "1024QAM"
        q = 10;
    otherwise
        q = NaN;
end
end

function nre = localNREFromGrant(grant, prbSet)
nre = NaN;
nrePerPRB = double(sixgr.util.structGet(grant, "NREPerPRB", NaN));
if isfinite(nrePerPRB) && nrePerPRB > 0 && ~isempty(prbSet)
    nre = double(nrePerPRB) * double(numel(prbSet));
end
end

function sizes = localCodeBlockSizes(layout)
count = localPositiveInteger(localFirstFiniteScalar( ...
    sixgr.util.structGet(layout, "NumCodeBlocks", NaN), ...
    sixgr.util.structGet(layout, "C", NaN)), 1);
cbLen = localFirstFiniteScalar( ...
    sixgr.util.structGet(layout, "CodeBlockLength", NaN), ...
    sixgr.util.structGet(layout, "K", NaN));
sizes = repmat(double(cbLen), 1, count);
end

function filler = localFillerBits(layout)
count = localPositiveInteger(localFirstFiniteScalar( ...
    sixgr.util.structGet(layout, "NumCodeBlocks", NaN), ...
    sixgr.util.structGet(layout, "C", NaN)), 1);
positions = sixgr.util.structGet(layout, "FillerPositions", cell(1, 0));
if iscell(positions) && ~isempty(positions)
    filler = zeros(1, max(count, numel(positions)));
    for i = 1:numel(positions)
        filler(i) = double(numel(positions{i}));
    end
    filler = filler(1:count);
    return;
end
total = localFirstFiniteScalar(sixgr.util.structGet(layout, "FillerCount", NaN), 0);
filler = repmat(double(total) / max(count, 1), 1, count);
end

function ncb = localNcbPerCodeBlock(layout)
count = localPositiveInteger(localFirstFiniteScalar( ...
    sixgr.util.structGet(layout, "NumCodeBlocks", NaN), ...
    sixgr.util.structGet(layout, "C", NaN)), 1);
motherLen = localFirstFiniteScalar( ...
    sixgr.util.structGet(layout, "MotherCodeLength", NaN), ...
    sixgr.util.structGet(layout, "N", NaN));
ncb = repmat(double(motherLen), 1, count);
end

function ratio = localSafeRatio(num, den)
ratio = NaN;
if isfinite(double(num)) && isfinite(double(den)) && double(den) > 0
    ratio = double(num) / double(den);
end
end

function hash = localContextHash(ctx)
payload = struct( ...
    "Direction", char(string(sixgr.util.structGet(ctx, "Direction", ""))), ...
    "CellId", double(sixgr.util.structGet(ctx, "CellId", NaN)), ...
    "UeId", double(sixgr.util.structGet(ctx, "UeId", NaN)), ...
    "RNTI", double(sixgr.util.structGet(ctx, "RNTI", NaN)), ...
    "HARQProcessId", double(sixgr.util.structGet(ctx, "HARQProcessId", NaN)), ...
    "NDIEpoch", double(sixgr.util.structGet(ctx, "NDIEpoch", NaN)), ...
    "NDI", logical(sixgr.util.structGet(ctx, "NDI", false)), ...
    "TBId", char(string(sixgr.util.structGet(ctx, "TBId", ""))), ...
    "CodewordId", double(sixgr.util.structGet(ctx, "CodewordId", NaN)), ...
    "FirstTxCanonicalSlot", double(sixgr.util.structGet(ctx, "FirstTxCanonicalSlot", NaN)), ...
    "OriginalGrantId", char(string(sixgr.util.structGet(ctx, "OriginalGrantId", ""))), ...
    "OriginalMCS", double(sixgr.util.structGet(ctx, "OriginalMCS", NaN)), ...
