function [group, status] = validateCodewordTBContexts(meta)
%VALIDATECODEWORDTBCONTEXTS Validate one HARQ TB context per codeword.
%
% A rank-5..8 PDSCH carries two independently coded transport blocks.
% This adapter preserves that ownership while exposing an explicitly
% aggregate group summary to grant-level callers.

if nargin < 1 || ~isstruct(meta) || ~isscalar(meta)
    error("sixgr:harq:BadCodewordContextMeta", ...
        "validateCodewordTBContexts requires one scalar meta struct.");
end

tbs = localPositiveIntegerRow(sixgr.util.structGet( ...
    meta, "TBSBitsPerCodeword", []), "TBSBitsPerCodeword");
nCodewords = numel(tbs);
if nCodewords < 1
    error("sixgr:harq:MissingCodewordTBS", ...
        "At least one codeword transport-block size is required.");
end
layouts = localCodingLayouts(sixgr.util.structGet( ...
    meta, "CodingLayouts", {}), nCodewords);
expectedTBS = localExpandNumericRow(sixgr.util.structGet( ...
    meta, "ExpectedTBSBitsPerCodeword", tbs), nCodewords, ...
    "ExpectedTBSBitsPerCodeword");
rateMatched = localExpandNumericRow(sixgr.util.structGet( ...
    meta, "RateMatchedBitsTotalPerCodeword", ...
    localLayoutScalars(layouts, "RateMatchedBitCount")), ...
    nCodewords, "RateMatchedBitsTotalPerCodeword");
rv = localExpandNumericRow(sixgr.util.structGet( ...
    meta, "RVPerCodeword", 0), nCodewords, "RVPerCodeword");
softEvidence = localExpandLogicalRow(sixgr.util.structGet( ...
    meta, "SoftCombiningEvidenceAvailablePerCodeword", false), ...
    nCodewords, "SoftCombiningEvidenceAvailablePerCodeword");
rateMatchedPerCB = localRateMatchedPerCB(meta, layouts, nCodewords);

grant = sixgr.util.structGet(meta, "Grant", struct());
if ~isstruct(grant) || ~isscalar(grant)
    error("sixgr:harq:BadCodewordGrant", ...
        "Codeword HARQ validation requires one scalar grant struct.");
end
direction = upper(strtrim(string(sixgr.util.structGet( ...
    meta, "Direction", sixgr.util.structGet(grant, "Direction", "")))));
if ~(direction == "DL" || direction == "UL")
    error("sixgr:harq:BadTBContextDirection", ...
        "HARQ codeword context direction must be DL or UL.");
end
isRetransmission = logical(sixgr.util.structGet( ...
    meta, "IsRetransmission", false));
previous = localPreviousContexts(sixgr.util.structGet( ...
    meta, "PreviousContext", struct()), nCodewords, isRetransmission);
rvSequence = double(sixgr.util.structGet( ...
    meta, "RVSequence", [0 2 3 1]));
baseTBId = localBaseTBId(grant, sixgr.util.structGet( ...
    meta, "PreviousContext", struct()));

contexts = cell(1, nCodewords);
statuses = cell(1, nCodewords);
for c = 1:nCodewords
    layout = layouts{c};
    grantCW = grant;
    grantCW.TBSBits = double(tbs(c));
    grantCW.TransportBlockSize = double(tbs(c));
    grantCW.ScheduledTransportBlockSize = double(tbs(c));
    grantCW.Codeword = double(c - 1);
    grantCW.CodewordIndex = double(c - 1);
    grantCW.TransportBlockId = char(baseTBId + "|cw=" + string(c - 1));
    grantCW.TBId = grantCW.TransportBlockId;
    grantCW.CodedBitCountG = double(rateMatched(c));
    grantCW.TargetCodeRate = double(sixgr.util.structGet( ...
        layout, "TargetCodeRate", NaN));
    grantCW.Modulation = char(string(sixgr.util.structGet( ...
        layout, "Modulation", "")));
    grantCW.NumLayers = double(sixgr.util.structGet( ...
        layout, "NumLayers", NaN));
    grantCW.Layers = grantCW.NumLayers;

    previousRV = double(sixgr.util.structGet( ...
        previous{c}, "LastObservedRV", NaN));
    metaCW = struct( ...
        "Direction", char(direction), ...
        "Grant", grantCW, ...
        "PHYGrant", sixgr.util.structGet(meta, "PHYGrant", struct()), ...
        "CodingLayout", layout, ...
        "PreviousContext", previous{c}, ...
        "TransportBlockContext", previous{c}, ...
        "IsRetransmission", isRetransmission, ...
        "RateMatchedBitsTotal", double(rateMatched(c)), ...
        "RateMatchedBitsPerCB", double(rateMatchedPerCB{c}), ...
        "TBSBits", double(tbs(c)), ...
        "ExpectedTBSBits", double(expectedTBS(c)), ...
        "CodewordId", double(c - 1), ...
        "TBId", grantCW.TransportBlockId, ...
        "RV", double(rv(c)), ...
        "PreviousRV", previousRV, ...
        "RVSequence", rvSequence, ...
        "SoftCombiningEvidenceAvailable", logical(softEvidence(c)), ...
        "PreviousCombinedLLRAvailable", logical(softEvidence(c)));
    [contexts{c}, statuses{c}] = ...
        sixgr.harq.validateTBContextForTransmission(metaCW);
    if round(double(contexts{c}.TBSBits)) ~= tbs(c) || ...
            round(double(contexts{c}.CodewordId)) ~= c - 1
        error("sixgr:harq:CodewordContextOwnershipMismatch", ...
            "HARQ context %d did not preserve its codeword TBS/identity.", ...
            c - 1);
    end
end

originalTBS = cellfun(@(s) double(s.OriginalTBSBits), statuses);
currentTBS = cellfun(@(s) double(s.CurrentTBSBits), statuses);
originalE = cellfun(@(s) double(s.OriginalRateMatchedBits), statuses);
currentE = cellfun(@(s) double(s.CurrentRateMatchedBits), statuses);
layoutHashes = string(cellfun(@(s) string(s.CodeBlockLayoutHash), ...
    statuses, "UniformOutput", false));
contextHashes = string(cellfun(@(s) string(s.HARQContextHash), ...
    statuses, "UniformOutput", false));
contextStates = string(cellfun(@(s) string(s.HARQContextStatus), ...
    statuses, "UniformOutput", false));

group = struct( ...
    "ContractVersion", "HARQCodewordContextGroup/v1", ...
    "Direction", char(direction), ...
    "CodewordCount", double(nCodewords), ...
    "CodewordIds", double(0:(nCodewords - 1)), ...
    "CodewordContexts", {contexts}, ...
    "TBSBitsPerCodeword", double(tbs), ...
    "TBSBits", double(sum(tbs)), ...
    "OriginalTBSBitsPerCodeword", double(originalTBS), ...
    "CurrentTBSBitsPerCodeword", double(currentTBS), ...
    "OriginalRateMatchedBitsPerCodeword", double(originalE), ...
    "CurrentRateMatchedBitsPerCodeword", double(currentE), ...
    "OriginalRateMatchedBitsTotal", double(sum(originalE)), ...
    "CurrentRateMatchedBitsTotal", double(sum(currentE)), ...
    "CodeBlockLayoutHashPerCodeword", layoutHashes, ...
    "HARQContextHashPerCodeword", contextHashes, ...
    "CodeBlockLayoutHash", char(localGroupHash( ...
        "codeblock-layout", layoutHashes)), ...
    "HARQContextHash", char(localGroupHash( ...
        "harq-context", contextHashes)), ...
    "RVSequence", double(rvSequence(:).'), ...
    "LastObservedRVPerCodeword", double(rv), ...
    "NDI", localCommonLogical(contexts, "NDI"), ...
    "NDIEpoch", localCommonNumeric(contexts, "NDIEpoch"), ...
    "HARQProcessId", localCommonNumeric(contexts, "HARQProcessId"), ...
    "TBId", char(baseTBId), ...
    "ShortIRRetx", logical(any(cellfun( ...
        @(s) logical(s.ShortIRRetx), statuses))));
group.EffectiveInitialCodeRate = localSafeRatio( ...
    sum(originalTBS), sum(originalE));
group.EffectiveCurrentTxCodeRate = localSafeRatio( ...
    sum(currentTBS), sum(currentE));

status = struct( ...
    "ContractVersion", "HARQCodewordContextGroupStatus/v1", ...
    "CodewordCount", double(nCodewords), ...
    "CodewordStatuses", {statuses}, ...
    "OriginalTBSBitsPerCodeword", double(originalTBS), ...
    "CurrentTBSBitsPerCodeword", double(currentTBS), ...
    "OriginalTBSBits", double(sum(originalTBS)), ...
    "CurrentTBSBits", double(sum(currentTBS)), ...
    "OriginalRateMatchedBitsPerCodeword", double(originalE), ...
    "CurrentRateMatchedBitsPerCodeword", double(currentE), ...
    "OriginalRateMatchedBits", double(sum(originalE)), ...
    "CurrentRateMatchedBits", double(sum(currentE)), ...
    "EffectiveInitialCodeRate", double(group.EffectiveInitialCodeRate), ...
    "EffectiveCurrentTxCodeRate", ...
        double(group.EffectiveCurrentTxCodeRate), ...
    "ShortIRRetx", logical(group.ShortIRRetx), ...
    "CodeBlockLayoutHash", group.CodeBlockLayoutHash, ...
    "HARQContextHash", group.HARQContextHash, ...
    "HARQContextStatus", char("per_codeword:" + ...
        strjoin(unique(contextStates, "stable"), "|")));
end

function layouts = localCodingLayouts(raw, n)
if iscell(raw)
    layouts = raw(:).';
elseif isstruct(raw)
    layouts = num2cell(raw(:).');
else
    layouts = {};
end
if numel(layouts) ~= n || any(cellfun( ...
        @(x) ~(isstruct(x) && isscalar(x) && ~isempty(fieldnames(x))), ...
        layouts))
    error("sixgr:harq:BadCodewordCodingLayouts", ...
        "CodingLayouts must contain exactly %d nonempty scalar structs.", n);
end
end

function values = localLayoutScalars(layouts, field)
values = cellfun(@(x) double(sixgr.util.structGet( ...
    x, field, NaN)), layouts);
end

function values = localPositiveIntegerRow(raw, label)
values = double(raw(:).');
if isempty(values) || any(~isfinite(values) | values <= 0 | ...
        values ~= fix(values))
    error("sixgr:harq:BadCodewordNumericVector", ...
        "%s must contain positive finite integers.", label);
end
end

function values = localExpandNumericRow(raw, n, label)
values = double(raw(:).');
if isscalar(values) && n > 1
    values = repmat(values, 1, n);
end
if numel(values) ~= n || any(~isfinite(values))
    error("sixgr:harq:BadCodewordNumericVector", ...
        "%s must contain one value per codeword.", label);
end
end

function values = localExpandLogicalRow(raw, n, label)
if ~(islogical(raw) || isnumeric(raw))
    error("sixgr:harq:BadCodewordLogicalVector", ...
        "%s must be logical/numeric.", label);
end
values = logical(raw(:).');
if isscalar(values) && n > 1
    values = repmat(values, 1, n);
end
if numel(values) ~= n
    error("sixgr:harq:BadCodewordLogicalVector", ...
        "%s must contain one value per codeword.", label);
end
end

function values = localRateMatchedPerCB(meta, layouts, n)
raw = sixgr.util.structGet(meta, "RateMatchedBitsPerCBPerCodeword", {});
if isempty(raw)
    values = cellfun(@(x) double(sixgr.util.structGet( ...
        x, "E_r", [])), layouts, "UniformOutput", false);
elseif iscell(raw)
    values = raw(:).';
else
    error("sixgr:harq:BadCodewordRateMatchedPerCB", ...
        "RateMatchedBitsPerCBPerCodeword must be a cell array.");
end
if numel(values) ~= n
    error("sixgr:harq:BadCodewordRateMatchedPerCB", ...
        "One rate-matched code-block vector is required per codeword.");
end
for c = 1:n
    values{c} = double(values{c}(:).');
    if isempty(values{c}) || any(~isfinite(values{c}) | values{c} <= 0)
        error("sixgr:harq:BadCodewordRateMatchedPerCB", ...
            "Codeword %d has an invalid rate-matched code-block vector.", ...
            c - 1);
    end
end
end

function previous = localPreviousContexts(raw, n, isRetransmission)
previous = repmat({struct()}, 1, n);
if ~(isstruct(raw) && isscalar(raw) && ~isempty(fieldnames(raw)))
    return;
end
if isfield(raw, "CodewordContexts")
    value = raw.CodewordContexts;
    if iscell(value)
        previous = value(:).';
    elseif isstruct(value)
        previous = num2cell(value(:).');
    end
    if numel(previous) ~= n
        error("sixgr:harq:PreviousCodewordContextCountMismatch", ...
            "Previous HARQ group contains %d contexts; expected %d.", ...
            numel(previous), n);
    end
elseif n == 1
    previous = {raw};
elseif logical(isRetransmission)
    error("sixgr:harq:LegacyContextCannotReplayTwoCodewords", ...
        "A two-codeword retransmission requires one prior TB context per codeword.");
end
end

function token = localBaseTBId(grant, previous)
token = string(sixgr.util.structGet(previous, "TBId", ""));
if strlength(strtrim(token)) == 0
    candidates = ["TransportBlockId","TBIdentity","TBId","GrantContextId"];
    for i = 1:numel(candidates)
        token = string(sixgr.util.structGet(grant, candidates(i), ""));
        if strlength(strtrim(token)) > 0
            break;
        end
    end
end
if strlength(strtrim(token)) == 0
    token = "harq_tb_group";
end
token = token(1);
end

function value = localCommonNumeric(values, field)
raw = cellfun(@(x) double(sixgr.util.structGet(x, field, NaN)), values);
finite = raw(isfinite(raw));
if isempty(finite)
    value = NaN;
elseif all(abs(finite - finite(1)) <= 1e-9)
    value = double(finite(1));
else
    error("sixgr:harq:CodewordContextGroupMismatch", ...
        "Per-codeword HARQ field %s is not common across the group.", field);
end
end

function value = localCommonLogical(values, field)
raw = cellfun(@(x) logical(sixgr.util.structGet(x, field, false)), values);
if ~all(raw == raw(1))
    error("sixgr:harq:CodewordContextGroupMismatch", ...
        "Per-codeword HARQ field %s is not common across the group.", field);
end
value = logical(raw(1));
end

function hash = localGroupHash(label, values)
payload = string(label) + "|" + strjoin(string(values(:).'), "|");
hash = string(sixgr.util.sha256Hex(payload));
end

function value = localSafeRatio(a, b)
if isfinite(a) && isfinite(b) && b > 0
    value = double(a) ./ double(b);
else
    value = NaN;
end
end
