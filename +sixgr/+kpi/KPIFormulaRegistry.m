function T = KPIFormulaRegistry()
%KPIFORMULAREGISTRY Canonical simulator KPI accounting formulas.
%   These are simulator accounting formulas derived from NR PHY/MAC evidence;
%   they are not normative 6G KPI definitions.

rows = [
    localRow("UL_PHY_ScheduledThroughput_Mbps", "UL", "PHY", "Mbps", ...
    "sum(ScheduledBits)/ScheduledResourceExposureSec/1e6", ...
    "ul_pusch_trials", "Direction,TBSize_bits,OfferedBits,AirInterfaceObservation_ms,Slot,Frame", ...
    "Direction == UL", "all_attempts", "not_applicable", true);
    localRow("DL_PHY_ScheduledThroughput_Mbps", "DL", "PHY", "Mbps", ...
    "sum(ScheduledBits)/ScheduledResourceExposureSec/1e6", ...
    "dl_pdsch_trials", "Direction,TBSize_bits,OfferedBits,AirInterfaceObservation_ms,Slot,Frame", ...
    "Direction == DL", "all_attempts", "not_applicable", true);
    localRow("UL_TB_Delivery_Goodput_Mbps", "UL", "PHY", "Mbps", ...
    "sum(first-success delivered GoodputBits where TBCrcPass=true)/MeasurementWindowSec/1e6", ...
    "ul_pusch_trials", "Direction,Goodput_Mbps,GoodBits,TBSize_bits,CRCPass,AirInterfaceObservation_ms,Slot,Frame", ...
    "Direction == UL", "deduplicate_transport_block", "crc_fail_zero_goodput", true);
    localRow("DL_TB_Delivery_Goodput_Mbps", "DL", "PHY", "Mbps", ...
    "sum(first-success delivered GoodputBits where TBCrcPass=true)/MeasurementWindowSec/1e6", ...
    "dl_pdsch_trials", "Direction,Goodput_Mbps,GoodBits,TBSize_bits,CRCPass,AirInterfaceObservation_ms,Slot,Frame", ...
    "Direction == DL", "deduplicate_transport_block", "crc_fail_zero_goodput", true);
    localRow("UL_BLER", "UL", "PHY", "ratio", ...
    "failed TB attempts / total TB attempts", ...
    "ul_pusch_trials", "Direction,CRCPass", ...
    "Direction == UL", "attempt_level", "crc_fail_counts_failed", true);
    localRow("DL_BLER", "DL", "PHY", "ratio", ...
    "failed TB attempts / total TB attempts", ...
    "dl_pdsch_trials", "Direction,CRCPass", ...
    "Direction == DL", "attempt_level", "crc_fail_counts_failed", true);
    localRow("UL_BER", "UL", "PHY", "ratio", ...
    "sum(BitErrors)/sum(BitsCompared)", ...
    "ul_pusch_trials", "Direction,BitErrors,BitsCompared", ...
    "Direction == UL", "weighted_by_bits_compared", "failed_rows_included_when_bits_present", true);
    localRow("DL_BER", "DL", "PHY", "ratio", ...
    "sum(BitErrors)/sum(BitsCompared)", ...
    "dl_pdsch_trials", "Direction,BitErrors,BitsCompared", ...
    "Direction == DL", "weighted_by_bits_compared", "failed_rows_included_when_bits_present", true);
    localRow("UL_Goodput_Max_Mbps", "UL", "PHY", "Mbps", ...
    "max(raw Goodput_Mbps over Direction=UL rows)", ...
    "ul_pusch_trials", "Direction,Goodput_Mbps", ...
    "Direction == UL", "row_maximum", "crc_fail_rows_contribute_their_raw_goodput_field", true);
    localRow("DL_Goodput_Max_Mbps", "DL", "PHY", "Mbps", ...
    "max(raw Goodput_Mbps over Direction=DL rows)", ...
    "dl_pdsch_trials", "Direction,Goodput_Mbps", ...
    "Direction == DL", "row_maximum", "crc_fail_rows_contribute_their_raw_goodput_field", true);
    localRow("UL_SpectralEfficiency_bpsHz", "UL", "PHY", "bps/Hz", ...
    "delivered bits / AggregationDurationSec / EffectiveBandwidthHz", ...
    "ul_pusch_trials", "Direction,GoodBits,Goodput_Mbps", ...
    "Direction == UL", "deduplicate_transport_block", "unavailable_without_bandwidth", false);
    localRow("DL_SpectralEfficiency_bpsHz", "DL", "PHY", "bps/Hz", ...
    "delivered bits / AggregationDurationSec / EffectiveBandwidthHz", ...
    "dl_pdsch_trials", "Direction,GoodBits,Goodput_Mbps", ...
    "Direction == DL", "deduplicate_transport_block", "unavailable_without_bandwidth", false);
    localRow("UL_MAC_Goodput_Mbps", "UL", "MAC", "Mbps", ...
    "sum(unique delivered MAC SDU payload bits)/AggregationDurationSec/1e6", ...
    "mac_ul_delivery", "Direction,MACSDUId,PayloadBits,DeliverySuccess,DurationSec", ...
    "Direction == UL && DeliverySuccess == true", "deduplicate_mac_sdu", "failed_sdu_zero_goodput", false);
    localRow("DL_MAC_Goodput_Mbps", "DL", "MAC", "Mbps", ...
    "sum(unique delivered MAC SDU payload bits)/AggregationDurationSec/1e6", ...
    "mac_dl_delivery", "Direction,MACSDUId,PayloadBits,DeliverySuccess,DurationSec", ...
    "Direction == DL && DeliverySuccess == true", "deduplicate_mac_sdu", "failed_sdu_zero_goodput", false);
    localRow("UL_Application_Goodput_Mbps", "UL", "application", "Mbps", ...
    "sum(unique delivered application payload bits)/AggregationDurationSec/1e6", ...
    "traffic_ul_packets", "Direction,PacketId,ApplicationPayloadBits,DeliverySuccess,DurationSec", ...
    "Direction == UL && DeliverySuccess == true", "deduplicate_application_packet", "failed_packet_zero_goodput", false);
    localRow("DL_Application_Goodput_Mbps", "DL", "application", "Mbps", ...
    "sum(unique delivered application payload bits)/AggregationDurationSec/1e6", ...
    "traffic_dl_packets", "Direction,PacketId,ApplicationPayloadBits,DeliverySuccess,DurationSec", ...
    "Direction == DL && DeliverySuccess == true", "deduplicate_application_packet", "failed_packet_zero_goodput", false);
    localRow("UL_HARQ_NACK_Rate", "UL", "HARQ", "ratio", ...
    "NACK events / ACK_NACK events", ...
    "received_harq_feedback_observations", "FeedbackForDirection,FeedbackOutcome,ObservedAck,ReceiverUsable,ObservationID,BitIndex", ...
    "Direction == UL", "event_count", "not_applicable", true);
    localRow("DL_HARQ_NACK_Rate", "DL", "HARQ", "ratio", ...
    "NACK events / ACK_NACK events", ...
    "received_harq_feedback_observations", "FeedbackForDirection,FeedbackOutcome,ObservedAck,ReceiverUsable,ObservationID,BitIndex", ...
    "Direction == DL", "event_count", "not_applicable", true);
    localRow("UL_Retransmission_Rate", "UL", "HARQ", "ratio", ...
    "retransmission TB attempts / total TB attempts", ...
    "live_harq_observation_timeline", "Direction,RV,IsRetransmission,TBId", ...
    "Direction == UL", "attempt_level", "not_applicable", true);
    localRow("DL_Retransmission_Rate", "DL", "HARQ", "ratio", ...
    "retransmission TB attempts / total TB attempts", ...
    "live_harq_observation_timeline", "Direction,RV,IsRetransmission,TBId", ...
    "Direction == DL", "attempt_level", "not_applicable", true);
    localRow("UL_PRB_Utilization", "UL", "scheduler", "ratio", ...
    "scheduled PRB-symbol resources / available PRB-symbol resources", ...
    "scheduler_ul_grants+slot_trace", "Direction,PRBStart,PRBCount,SymbolStart,NumSymbols;CanonicalSlot,ULSymbolStart,ULNumSymbols", ...
    "Direction == UL", "exact_prb_symbol_union", "not_applicable", true);
    localRow("DL_PRB_Utilization", "DL", "scheduler", "ratio", ...
    "scheduled PRB-symbol resources / available PRB-symbol resources", ...
    "scheduler_dl_grants+slot_trace", "Direction,PRBStart,PRBCount,SymbolStart,NumSymbols;CanonicalSlot,DLSymbolStart,DLNumSymbols", ...
    "Direction == DL", "exact_prb_symbol_union", "not_applicable", true);
    localRow("UL_Latency_ms", "UL", "traffic", "ms", ...
    "sum(first-delivery packet latency_ms)/unique delivered packet count", ...
    "application_packets", "Direction,PacketId,EnqueueTime_s,DeliveryTime_s,DeliverySuccess", ...
    "Direction == UL && DeliverySuccess == true", "first_delivery_per_scoped_packet", "failed_packets_not_delivered", false);
    localRow("DL_Latency_ms", "DL", "traffic", "ms", ...
    "sum(first-delivery packet latency_ms)/unique delivered packet count", ...
    "application_packets", "Direction,PacketId,EnqueueTime_s,DeliveryTime_s,DeliverySuccess", ...
    "Direction == DL && DeliverySuccess == true", "first_delivery_per_scoped_packet", "failed_packets_not_delivered", false);
    localRow("UL_TB_Delivery_Latency_ms", "UL", "PHY", "ms", ...
    "sum(first CRC-success end minus first transmission start in ms)/unique delivered TB count", ...
    "ul_pusch_trials", "Direction,TransportBlockId,CRCPass,GoodBits", ...
    "Direction == UL && CRCPass == true", "first_success_per_transport_block", "no_delivery_is_unavailable", false);
    localRow("DL_TB_Delivery_Latency_ms", "DL", "PHY", "ms", ...
    "sum(first CRC-success end minus first transmission start in ms)/unique delivered TB count", ...
    "dl_pdsch_trials", "Direction,TransportBlockId,CRCPass,GoodBits", ...
    "Direction == DL && CRCPass == true", "first_success_per_transport_block", "no_delivery_is_unavailable", false);
    localRow("Scenario_Total_UL_DeliveredBits", "scenario", "PHY", "bits", ...
    "sum(unique UL delivered transport-block bits)", ...
    "ul_pusch_trials", "Direction,TransportBlockId,GoodBits,CRCPass", ...
    "Direction == UL && CRCPass == true", "deduplicate_transport_block", "crc_fail_zero_goodput", true);
    localRow("Scenario_Total_DL_DeliveredBits", "scenario", "PHY", "bits", ...
    "sum(unique DL delivered transport-block bits)", ...
    "dl_pdsch_trials", "Direction,TransportBlockId,GoodBits,CRCPass", ...
    "Direction == DL && CRCPass == true", "deduplicate_transport_block", "crc_fail_zero_goodput", true);
    localRow("Scenario_Total_UL_ScheduledBits", "scenario", "PHY", "bits", ...
    "sum(UL scheduled TB attempt bits including retransmissions)", ...
    "ul_pusch_trials", "Direction,TBSize_bits,ScheduledBits,TBS", ...
    "Direction == UL", "all_attempts", "not_applicable", true);
    localRow("Scenario_Total_DL_ScheduledBits", "scenario", "PHY", "bits", ...
    "sum(DL scheduled TB attempt bits including retransmissions)", ...
    "dl_pdsch_trials", "Direction,TBSize_bits,ScheduledBits,TBS", ...
    "Direction == DL", "all_attempts", "not_applicable", true)
    ];

T = struct2table(rows);
T.FormulaVersion(endsWith(T.KPIName,"_Latency_ms"))="kpi_latency_population_v3";
end

function row = localRow(name, direction, layer, units, equation, sourceTables, requiredColumns, predicate, duplicateHandling, failedTBHandling, strictAllowed)
row = struct( ...
    "KPIName", string(name), ...
    "Direction", string(direction), ...
    "Layer", string(layer), ...
    "Units", string(units), ...
    "NumeratorDefinition", string(equation), ...
    "DenominatorDefinition", "see FormulaEquation", ...
    "TimeWindowDefinition", "scheduled metrics use resource exposure; delivered goodput uses measurement window", ...
    "RequiredSourceTables", string(sourceTables), ...
    "RequiredColumns", string(requiredColumns), ...
    "FilterPredicate", string(predicate), ...
    "DuplicateHandling", string(duplicateHandling), ...
    "HARQHandling", string(duplicateHandling), ...
    "FailedTBHandling", string(failedTBHandling), ...
    "MissingRowBehavior", "strict_fail_if_mandatory", ...
    "ProxyRowBehavior", "exclude_and_fail_if_only_proxy_rows", ...
    "RoundingPolicy", "double_precision_no_display_rounding", ...
    "Tolerance", 1e-9, ...
    "StrictAllowed", logical(strictAllowed), ...
    "FormulaVersion", "kpi_registry_v2", ...
    "ProducerModule", "sixgr.kpi.KPIFormulaRegistry", ...
    "FormulaEquation", string(equation), ...
    "Status", "active");
end
