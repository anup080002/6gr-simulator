function bits=transportGoodputBits(T)
%TRANSPORTGOODPUTBITS Consume runtime credit or derive it from retained rows.
% A sliced runtime table may contain a duplicate whose first delivery is not
% in the slice: preserve the original causal credit instead of awarding again.
if ~ismember('UniqueDeliveredTBBits',T.Properties.VariableNames)
    T=sixgr.kpi.creditTransportGoodput(T);
end
required={'TransportGoodputContract','TransportGoodputStatus', ...
    'FirstSuccessfulTBDelivery','TransportGoodputKey'};
assert(all(ismember(required,T.Properties.VariableNames)), ...
    'sixgr:kpi:MissingTransportGoodputContract','Unique delivered bits require their producer contract.');
assert(all(string(T.TransportGoodputContract)=="TransportGoodput/v1"), ...
    'sixgr:kpi:UnknownTransportGoodputContract','Unsupported transport-goodput producer contract.');
bits=double(T.UniqueDeliveredTBBits);
status=string(T.TransportGoodputStatus);
first=status=="first_crc_success";
zero=ismember(status,["crc_failure_no_delivery","repeated_crc_success_no_new_payload"]);
assert(all(isnan(bits) | (isfinite(bits)&bits>=0&bits==fix(bits))) && ...
    all(bits(zero)==0) && all(bits(first)>0) && ...
    all(isnan(bits(~first&~zero))) && isequal(logical(T.FirstSuccessfulTBDelivery),first), ...
    'sixgr:kpi:InvalidTransportGoodputCredit','Transport-goodput credit disagrees with its evidence status.');
% Validate the credit against retained receiver facts, not just a status
% string. Rebuilding evidence here never overwrites the streaming credit:
% an independently sliced repeated-success row must still contribute zero.
[evidence,ledger]=sixgr.kpi.creditTransportGoodput(T);
success=first | status=="repeated_crc_success_no_new_payload";
sourceSuccess=ismember(evidence.TransportGoodputStatus, ...
    ["first_crc_success","repeated_crc_success_no_new_payload"]);
retainedKeys=string(T.TransportGoodputKey);
% CSV string import represents an explicitly empty key as missing. Empty
% keys are legal only when the unchanged CRC/identity/status reconstruction
% below also produces no key; this does not manufacture a successful TB ID.
retainedKeys(ismissing(retainedKeys))="";
assert(all(success==sourceSuccess) && ...
    all(status(~success)==evidence.TransportGoodputStatus(~success)) && ...
    all(retainedKeys==evidence.TransportGoodputKey), ...
    'sixgr:kpi:InvalidTransportGoodputCredit', ...
    'Transport-goodput credit must retain matching CRC, TB identity and experiment scope.');
[found,index]=ismember(string(T.TransportGoodputKey(first)),ledger.Key);
assert(all(found) && all(bits(first)==ledger.PayloadBits(index)) && ...
    numel(unique(string(T.TransportGoodputKey(first))))==nnz(first), ...
    'sixgr:kpi:InvalidTransportGoodputCredit', ...
    'Each logical TB can receive exactly its actual payload size at most once.');
end
