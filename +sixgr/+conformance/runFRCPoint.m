function [delivered, attempts, evidence] = ...
        localRunIndependentTransportBlock(entry, carrierTemplate, execution, ...
        cfg, precoder, tbBits, snr_dB, snrIndex,transportBlockIndex,opt)
carrier = localCloneCarrier(carrierTemplate);
channelSeed = double(opt.Seed) + 7919 * double(snrIndex) + ...
    104729 * double(transportBlockIndex);
propagation = localCreatePropagation(entry, carrier, execution, channelSeed);
cleanup = onCleanup(@() localReleasePropagation(propagation)); %#ok<NASGU>
plannedTransmissionsBeforeTB = (double(transportBlockIndex) - 1) * ...
    double(entry.harq.max_transmissions);
[delivered, attempts, evidence, propagation] = localRunTransportBlock( ...
    entry, carrier, cfg, precoder, propagation, tbBits, snr_dB, ...
    snrIndex, plannedTransmissionsBeforeTB,transportBlockIndex,opt);
if string(entry.condition.kind) == "fading"
    evidence.Seeds.FadingChannelSeed = localFoldSeed(channelSeed);
else
    evidence.Seeds.FadingChannelSeed = NaN;
end
end

function [delivered, attempts, evidence, propagation] = ...
        localRunTransportBlock(entry, carrier, cfg, precoder, propagation, ...
        tbBits, snr_dB, snrIndex, transmissionsBeforeTB, ...
        transportBlockIndex, opt)
softBuffer = [];
softLayout = struct();
delivered = false;
attempts = 0;
evidence = struct( ...
    "Tx", struct(), ...
    "Rx", struct(), ...
    "Noise", struct(), ...
    "AttemptTx", {cell(0, 1)}, ...
    "AttemptRx", {cell(0, 1)}, ...
    "Propagation", localCompactPropagationEvidence(propagation), ...
    "Timing", struct(), ...
    "Seeds", struct( ...
        "FadingChannelSeed", NaN, ...
        "NoiseSeedByAttempt", zeros(0, 1), ...
        "RVByAttempt", zeros(0, 1)));
rvSequence = double(entry.harq.rv_sequence(:).');
timing = sixgr.conformance.buildFRCHARQTimeline( ...
    entry, double(transportBlockIndex), numel(rvSequence));
absoluteSlotByAttempt = zeros(numel(rvSequence), 1, "uint64");
channelStartSampleByAttempt = zeros(numel(rvSequence), 1, "uint64");
advanceSamplesByAttempt = zeros(numel(rvSequence), 1, "uint64");
previousSlot = NaN;
previousSlotSamples = NaN;

for rvIndex = 1:numel(rvSequence)
    attempts = attempts + 1;
    transmissionIndex = transmissionsBeforeTB + attempts;
    absoluteSlot = double(timing.AbsoluteSlotByAttempt(rvIndex));
    if rvIndex > 1
        slotGap = absoluteSlot - previousSlot;
        [propagation, advanceSamples] = localAdvancePropagationToSlot( ...
            propagation, previousSlotSamples, slotGap);
        advanceSamplesByAttempt(rvIndex) = uint64(advanceSamples);
    end
    carrier = localSetCarrierAbsoluteSlot(carrier, absoluteSlot);
    rv = rvSequence(rvIndex);
    absoluteSlotByAttempt(rvIndex) = uint64(absoluteSlot);
    channelStartSampleByAttempt(rvIndex) = ...
        uint64(propagation.SamplesProcessed);

    if string(entry.direction) == "downlink"
        txPDSCH = localConfigurePDSCHForSlot( ...
            entry, carrier, propagation.PhysicalChannel);
        txPrecoder = localPDSCHPrecoderForSlot( ...
            entry, carrier, cfg, double(opt.Seed) + transmissionIndex);
        trackingSlot = localIsDLTrackingSlot(entry, absoluteSlot);
        [tx, txInfo] = sixgr.phy.dl.PDSCH_Tx(cfg, ...
            "Carrier", carrier, ...
            "PDSCH", txPDSCH, ...
            "TransportBlockBits", tbBits, ...
            "TransportBlockSizeOverride", double(entry.coding.tbs_bits), ...
            "RV", rv, ...
            "TargetCodeRate", propagation.TargetCodeRate, ...
            "XOverhead", 0, ...
            "NumTxAnt", double(entry.mimo.tx_antennas), ...
            "PrecodingMatrix", txPrecoder, ...
            "ExecutionProfile", "phy_calibration", ...
            "CompactOutput", ~trackingSlot);
        if trackingSlot
            tx = localMaterializeTrackingCSIRS(entry, carrier, tx);
        end
    else
        [tx, txInfo] = sixgr.phy.ul.PUSCH_Tx(cfg, ...
            "Carrier", carrier, ...
            "PUSCH", propagation.PhysicalChannel, ...
            "TransportBlockBits", tbBits, ...
            "TransportBlockSizeOverride", double(entry.coding.tbs_bits), ...
            "RV", rv, ...
            "TargetCodeRate", propagation.TargetCodeRate, ...
            "XOverhead", 0, ...
            "NumTxAnt", double(entry.mimo.tx_antennas), ...
            "CompactOutput", true);
    end
    localAssertExactTx(entry, tx, transmissionIndex);

    previousSlotSamples = size(tx.Waveform, 1);
    previousSlot = absoluteSlot;
    attemptStartSample = double(propagation.SamplesProcessed);
    [channelWaveform, propagation] = localApplyPropagation( ...
        tx.Waveform, propagation);
    channelWaveform = localApplyCFO(channelWaveform, ...
        propagation.SampleRate_Hz, double(entry.condition.frequency_offset_hz), ...
        attemptStartSample);
    noiseSeed = localFoldSeed(double(opt.Seed) + ...
        1000003 * snrIndex + 1009 * transmissionIndex + 17 * rvIndex);
    evidence.Seeds.NoiseSeedByAttempt(end + 1, 1) = noiseSeed;
    evidence.Seeds.RVByAttempt(end + 1, 1) = rv;
    if string(entry.direction) == "downlink"
        [rxWaveform, noiseInfo] = sixgr.conformance.addReferenceNoise( ...
            channelWaveform, carrier, snr_dB, "Seed", noiseSeed);
        configuredNoiseVarianceSource = ...
            "sixgr.conformance.addReferenceNoise_unit_grid_contract";
    else
        % TS 38.104 defines UL SNR from total slot signal energy and
        % transmission-bandwidth noise energy, not directly as occupied
        % data-RE Es/N0. Convert through the exact PUSCH data/DM-RS energy
        % accounting while leaving the DL noise primitive unchanged.
        [rxWaveform, noiseInfo] = ...
            sixgr.conformance.addPUSCHReferenceNoise( ...
            channelWaveform, carrier, tx.PUSCH, snr_dB, ...
            "DMRSPowerScale", double(tx.DMRSPowerScale), ...
            "Seed", noiseSeed);
        configuredNoiseVarianceSource = ...
            "sixgr.conformance.addPUSCHReferenceNoise_ts38104_slot_energy_contract";
    end

    rxArgs = { ...
        "Carrier", carrier, ...
        "TransportBlockSize", double(entry.coding.tbs_bits), ...
        "TargetCodeRate", propagation.TargetCodeRate, ...
        "RV", rv, ...
        "NoiseVar", double(noiseInfo.SampleNoiseVariance), ...
        "NoiseVarDomain", "time", ...
        "HARQSoftBufferLLR", softBuffer, ...
        "HARQSoftBufferLayout", softLayout, ...
        "CodingLayout", tx.CodingLayout, ...
        "CompactOutput", true, ...
        "FastAWGNPath", false, ...
        "SkipTimingEstimate", propagation.SkipTimingEstimate};
    if ~isempty(opt.MaxDecoderIterations)
        rxArgs = [rxArgs, {"MaxIterations", double(opt.MaxDecoderIterations)}]; %#ok<AGROW>
    end

    if string(entry.direction) == "downlink"
        [rx, rxInfo] = sixgr.phy.dl.PDSCH_Rx(rxWaveform, cfg, ...
            rxArgs{:}, ...
            "PDSCH", tx.PDSCH, ...
            "PDSCHIndices", tx.PDSCHIndices, ...
            "CodingPlan", tx.CodingPlans, ...
            "CalibrationReceiverBundle", sixgr.util.structGet( ...
                txInfo,"CalibrationReceiverBundle",struct()), ...
            "ExecutionProfile", "phy_calibration", ...
            "PrecodingMatrix", txPrecoder);
    else
        [rx, rxInfo] = sixgr.phy.ul.PUSCH_Rx(rxWaveform, cfg, ...
            rxArgs{:}, ...
            "PUSCH", tx.PUSCH, ...
            "PUSCHIndices", tx.PUSCHIndices, ...
            "ConfiguredNoiseVariance", double(noiseInfo.SampleNoiseVariance), ...
            "ConfiguredNoiseVarianceSource", ...
                configuredNoiseVarianceSource, ...
            "StrictNoiseVarianceRequired", true);
    end
    localAssertTruthReceiver(entry, tx, rx);

    evidence.Noise = noiseInfo;
    evidence.Tx = localCompactTxEvidence(tx, txInfo);
    evidence.Rx = localCompactRxEvidence(rx, rxInfo);
    evidence.AttemptTx{end + 1, 1} = evidence.Tx;
    evidence.AttemptRx{end + 1, 1} = evidence.Rx;
    evidence.Timing = localFinalizeHARQTimingEvidence( ...
        timing, absoluteSlotByAttempt(1:attempts), ...
        channelStartSampleByAttempt(1:attempts), ...
        advanceSamplesByAttempt(1:attempts));
    if logical(rx.Ok)
        delivered = true;
        return;
    end
    softBuffer = rx.HARQSoftBuffer;
    softLayout = tx.CodingLayout;
end
end

