            oneSidedUpper <= double(requirement.target_fraction);
    case "greater_than_or_equal"
        tf = isfinite(oneSidedLower) && ...
            oneSidedLower >= double(requirement.target_fraction);
    otherwise
        tf = false;
end
tf = logical(tf);
end

