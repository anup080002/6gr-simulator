function slot = localSlotNumber(entry, transmissionIndex)
if string(entry.direction) ~= "downlink"
    slot = transmissionIndex - 1;
    return;
end
% Slot 0 carries the periodic SS/PBCH block and no PDSCH in these FRCs.
% Slots 1:19 carry PDSCH; slots 10 and 11 additionally carry the exact
% two-resource tracking CSI-RS reservation from Table 5.2-1.
periodIndex = floor((transmissionIndex - 1) / 19);
slotWithinPeriod = mod(transmissionIndex - 1, 19) + 1;
slot = 20 * periodIndex + slotWithinPeriod;
end

