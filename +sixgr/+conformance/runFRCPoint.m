function entry = localResolveEntry(entries, frcId, conditionId)
frcId = strtrim(string(frcId));
conditionId = strtrim(string(conditionId));
if strlength(frcId) == 0
    error("sixgr:conformance:EmptyFRCId", "FRC id must not be empty.");
end

matches = false(numel(entries), 1);
for index = 1:numel(entries)
    candidate = localSequenceItem(entries, index);
    idMatch = string(candidate.id) == frcId;
    standardMatch = string(candidate.frc_id) == frcId;
    conditionMatch = strlength(conditionId) == 0 || ...
        string(candidate.condition.id) == conditionId;
    matches(index) = (idMatch || standardMatch) && conditionMatch;
end
indices = find(matches);
if isempty(indices)
    if strlength(conditionId) == 0
        suffix = "";
    else
        suffix = " with condition '" + conditionId + "'";
    end
    error("sixgr:conformance:FRCPointNotFound", ...
        "No FRC catalog entry matches '%s'%s.", frcId, suffix);
end
if numel(indices) > 1
    conditions = strings(numel(indices), 1);
    for i = 1:numel(indices)
        candidate = localSequenceItem(entries, indices(i));
        conditions(i) = string(candidate.condition.id);
    end
    error("sixgr:conformance:AmbiguousFRCPoint", ...
        "FRC '%s' has multiple conditions (%s); provide conditionId.", ...
        frcId, strjoin(conditions, ", "));
end
entry = localSequenceItem(entries, indices);
if strlength(conditionId) > 0 && string(entry.condition.id) ~= conditionId
    error("sixgr:conformance:FRCConditionMismatch", ...
        "Entry '%s' uses condition '%s', not '%s'.", ...
        string(entry.id), string(entry.condition.id), conditionId);
end
end

function value = localSequenceItem(sequence, index)
if iscell(sequence)
    value = sequence{index};
else
    value = sequence(index);
end
end

function opt = localFinalizeOptions(opt, entry, policy)
profile = lower(string(opt.ExecutionProfile));
metric = string(entry.requirement.metric);
target = double(entry.requirement.target_fraction);
confidence = double(opt.ConfidenceLevel);
if profile == "smoke"
    defaults = struct( ...
        "MinTransportBlocks", 2, ...
        "MaxTransportBlocks", 8, ...
        "BatchSize", 1, ...
        "MaxConfidenceHalfWidth", 0.49);
    opt.ConfidenceEarlyStoppingEnabled = true;
    opt.ConfidenceQualificationEligible = false;
    opt.RequiredQualificationTransportBlocks = NaN;
    opt.ConfidenceSamplingPlan = ...
        "adaptive_smoke_descriptive_intervals_not_for_qualification";
elseif metric == "block_error_rate" && target <= 1e-4
    % The project gate makes two prespecified directional comparisons at
    % required SNR +/- tolerance. The two-sided interval endpoints are
    % one-sided 1-alpha/2 bounds, so Bonferroni provides the requested joint
    % confidence. Size a zero-error high endpoint so its upper bound is no
    % larger than target. The low endpoint is qualified by its directional
    % lower bound; its metric-interval half-width is not an SNR precision
    % requirement.
    % The standards reference-point decision is one-sided.  Do not apply
    % the alpha/2 penalty used by the optional two-endpoint symmetric
    % regression diagnostic to this normative-direction sample floor.
    zeroErrorQualificationCount = ceil( ...
        log(1 - confidence) / log(1 - target));
    defaults = struct( ...
        "MinTransportBlocks", 1000, ...
        "MaxTransportBlocks", zeroErrorQualificationCount, ...
        "BatchSize", 100, ...
        "MaxConfidenceHalfWidth", max(target / 2, eps));
    opt.ConfidenceEarlyStoppingEnabled = false;
    opt.RequiredQualificationTransportBlocks = zeroErrorQualificationCount;
    opt.ConfidenceSamplingPlan = ...
        "fixed_max_transport_blocks_prespecified_snr_tolerance_bracket";
else
    z = sqrt(2) * erfcinv(1 - confidence);
    worstCaseQualificationCount = ceil(z^2 / ...
        (4 * 0.01^2));
    defaults = struct( ...
        "MinTransportBlocks", 1000, ...
        "MaxTransportBlocks", max(10000, worstCaseQualificationCount), ...
        "BatchSize", 25, ...
        "MaxConfidenceHalfWidth", 0.01);
    opt.ConfidenceEarlyStoppingEnabled = false;
    opt.RequiredQualificationTransportBlocks = ...
        worstCaseQualificationCount;
    opt.ConfidenceSamplingPlan = ...
        "fixed_max_transport_blocks_prespecified_snr_tolerance_bracket";
end
for name = ["MinTransportBlocks", "MaxTransportBlocks", ...
        "BatchSize", "MaxConfidenceHalfWidth"]
    if isempty(opt.(name))
        opt.(name) = defaults.(name);
    end
end
if double(opt.MaxTransportBlocks) < double(opt.MinTransportBlocks)
    error("sixgr:conformance:InvalidSamplingBounds", ...
        "MaxTransportBlocks must be at least MinTransportBlocks.");
end
if profile == "full"
    % Fixed-sample intervals retain their stated interpretation. Repeated
    % confidence peeking and stopping would require an anytime-valid
    % confidence sequence, which these CP/delta intervals are not.
    opt.StopWhenConfidenceSeparated = false;
    opt.ConfidenceQualificationEligible = ...
        double(opt.MaxTransportBlocks) >= ...
        double(opt.RequiredQualificationTransportBlocks);
end
if isempty(opt.Tolerance_dB)
    opt.Tolerance_dB = double(policy.tolerance_db);
end
end

function [snr, seedIndices] = localResolveSNRGrid( ...
        requested, required, tolerance, executionProfile, ...
        evaluateSymmetricRegression)
required = double(required);
tolerance = double(tolerance);
if isempty(requested)
    % The full qualification makes exactly two prespecified directional
    % comparisons at required +/- tolerance, plus the required point. The
    % former seven-point exploratory grid did not contribute any additional
    % qualification decision and multiplied the fixed-sample truth runtime.
    %
    % Keep its sorted positions as RNG seed indices for the three retained
    % points. This makes their payload, channel, and noise trials bit-for-bit
    % identical to the legacy full sweep. Smoke runs retain all exploratory
    % points, and an explicit caller grid remains unchanged.
    legacy = unique([required + [-2, -1, -0.5, 0, 0.5, 1, 2], ...
        required, required - tolerance, required + tolerance], "sorted");
    if ~logical(evaluateSymmetricRegression)
        snr = required;
        seedIndices = find(abs(legacy - required) <= 1e-12, 1);
        return;
    end
    if lower(string(executionProfile)) == "full"
        snr = unique([required - tolerance, required, ...
            required + tolerance], "sorted");
        seedIndices = zeros(size(snr));
        for index = 1:numel(snr)
            legacyIndex = find(abs(legacy - snr(index)) <= 1e-12, 1);
            if isempty(legacyIndex)
                error("sixgr:conformance:SNRSeedPlanMismatch", ...
                    "Qualification SNR %.12g dB is absent from the legacy seed plan.", ...
                    snr(index));
            end
            seedIndices(index) = legacyIndex;
        end
        return;
    end
    snr = legacy;
else
    snr = double(requested(:).');
    if logical(evaluateSymmetricRegression)
        snr = unique([snr, required, required - tolerance, ...
            required + tolerance], "sorted");
    else
        snr = unique([snr, required], "sorted");
    end
end
seedIndices = 1:numel(snr);
end

