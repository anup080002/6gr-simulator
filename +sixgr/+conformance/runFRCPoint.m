function [delivered, attempts, evidence] = ...
        localRunIndependentTransportBlock(entry, carrierTemplate, execution, ...
        cfg, precoder, tbBits, snr_dB, snrIndex,transportBlockIndex,opt)
carrier = localCloneCarrier(carrierTemplate);
channelSeed = double(opt.Seed) + 7919 * double(snrIndex) + ...
    104729 * double(transportBlockIndex);
propagation = localCreatePropagation(entry, carrier, execution, channelSeed, opt);
cleanup = onCleanup(@() localReleasePropagation(propagation)); %#ok<NASGU>
plannedTransmissionsBeforeTB = (double(transportBlockIndex) - 1) * ...
    double(entry.harq.max_transmissions);
[delivered, attempts, evidence, propagation] = localRunTransportBlock( ...
    entry, carrier, cfg, precoder, propagation, tbBits, snr_dB, ...
    snrIndex, plannedTransmissionsBeforeTB,transportBlockIndex,opt);
if string(entry.condition.kind) == "fading"
    evidence.Seeds.FadingChannelSeed = localFoldSeed(channelSeed);
else
    evidence.Seeds.FadingChannelSeed = NaN;
end
end

function [delivered, attempts, evidence, propagation] = ...
        localRunTransportBlock(entry, carrier, cfg, precoder, propagation, ...
        tbBits, snr_dB, snrIndex, transmissionsBeforeTB, ...
        transportBlockIndex, opt)
softBuffer = [];
softLayout = struct();
delivered = false;
attempts = 0;
evidence = struct( ...
    "Tx", struct(), ...
    "Rx", struct(), ...
    "Noise", struct(), ...
    "AttemptTx", {cell(0, 1)}, ...
    "AttemptRx", {cell(0, 1)}, ...
    "Propagation", localCompactPropagationEvidence(propagation), ...
    "Timing", struct(), ...
    "Seeds", struct( ...
        "FadingChannelSeed", NaN, ...
        "NoiseSeedByAttempt", zeros(0, 1), ...
        "RVByAttempt", zeros(0, 1)));
rvSequence = double(entry.harq.rv_sequence(:).');
timing = sixgr.conformance.buildFRCHARQTimeline( ...
    entry, double(transportBlockIndex), numel(rvSequence));
if string(entry.direction) == "downlink"
    timing = localAlignDLTimelineToStandardFrame( ...
        timing, transportBlockIndex, numel(rvSequence));
else
    timing = localAlignULTimelineToStandardWaveform( ...
        timing, transportBlockIndex, numel(rvSequence));
end
absoluteSlotByAttempt = zeros(numel(rvSequence), 1, "uint64");
channelStartSampleByAttempt = zeros(numel(rvSequence), 1, "uint64");
advanceSamplesByAttempt = zeros(numel(rvSequence), 1, "uint64");
previousSlot = NaN;
previousSlotSamples = NaN;

dlFrame = struct();
dlFrameChannelWaveform = [];
dlFrameStartSample = double(propagation.SamplesProcessed);
ulFrame = struct();
ulFrameChannelWaveform = [];
ulFrameStartSample = double(propagation.SamplesProcessed);
if string(entry.direction) == "downlink"
    dlFrame = localBuildStatisticalDownlinkFrame( ...
        entry, carrier, propagation, cfg, tbBits, timing, ...
        rvSequence, transmissionsBeforeTB, opt);
    [dlFrameChannelWaveform, propagation] = localApplyPropagation( ...
        dlFrame.Waveform, propagation);
    dlFrameChannelWaveform = localApplyCFO( ...
        dlFrameChannelWaveform, propagation.SampleRate_Hz, ...
        double(entry.condition.frequency_offset_hz), dlFrameStartSample);
    evidence.Propagation = localCompactPropagationEvidence(propagation);
    evidence.Propagation.StandardDownlinkFrame = dlFrame.Evidence;
else
    ulFrame = localBuildStatisticalUplinkWaveform( ...
        entry, carrier, propagation, cfg, tbBits, timing, ...
        rvSequence, transmissionsBeforeTB);
    [ulFrameChannelWaveform, propagation] = localApplyPropagation( ...
        ulFrame.Waveform, propagation);
    ulFrameChannelWaveform = localApplyCFO( ...
        ulFrameChannelWaveform, propagation.SampleRate_Hz, ...
        double(entry.condition.frequency_offset_hz), ulFrameStartSample);
    evidence.Propagation = localCompactPropagationEvidence(propagation);
    evidence.Propagation.StandardUplinkWaveform = ulFrame.Evidence;
end

for rvIndex = 1:numel(rvSequence)
    attempts = attempts + 1;
    transmissionIndex = transmissionsBeforeTB + attempts;
    absoluteSlot = double(timing.AbsoluteSlotByAttempt(rvIndex));
    carrier = localSetCarrierAbsoluteSlot(carrier, absoluteSlot);
    rv = rvSequence(rvIndex);
    absoluteSlotByAttempt(rvIndex) = uint64(absoluteSlot);

    if string(entry.direction) == "downlink"
        tx = dlFrame.AttemptTx{rvIndex};
        txInfo = dlFrame.AttemptTxInfo{rvIndex};
        txPrecoder = dlFrame.AttemptPrecoder{rvIndex};
    else
        tx = ulFrame.AttemptTx{rvIndex};
        txInfo = ulFrame.AttemptTxInfo{rvIndex};
    end
    localAssertExactTx(entry, tx, transmissionIndex);

    if string(entry.direction) == "downlink"
        previousSlotSamples = double(dlFrame.SamplesPerSlot);
        previousSlot = absoluteSlot;
        attemptStartSample = dlFrameStartSample + ...
            double(dlFrame.TargetSampleOffset(rvIndex));
        channelWaveform = localSliceStandardDLTarget( ...
            dlFrameChannelWaveform, dlFrame, rvIndex, propagation);
    else
        previousSlotSamples = double(ulFrame.SamplesPerSlot);
        previousSlot = absoluteSlot;
        attemptStartSample = ulFrameStartSample + ...
            double(ulFrame.TargetSampleOffset(rvIndex));
        channelWaveform = localSliceStandardULTarget( ...
            ulFrameChannelWaveform, ulFrame, rvIndex, propagation);
    end
    channelStartSampleByAttempt(rvIndex) = uint64(attemptStartSample);
    noiseSeed = localFoldSeed(double(opt.Seed) + ...
        1000003 * snrIndex + 1009 * transmissionIndex + 17 * rvIndex);
    evidence.Seeds.NoiseSeedByAttempt(end + 1, 1) = noiseSeed;
    evidence.Seeds.RVByAttempt(end + 1, 1) = rv;
    if string(entry.direction) == "downlink"
        [rxWaveform, noiseInfo] = sixgr.conformance.addReferenceNoise( ...
            channelWaveform, carrier, snr_dB, "Seed", noiseSeed);
        configuredNoiseVarianceSource = ...
            "sixgr.conformance.addReferenceNoise_unit_grid_contract";
    else
        % TS 38.104 defines UL SNR from total slot signal energy and
        % transmission-bandwidth noise energy, not directly as occupied
        % data-RE Es/N0. Convert through the exact PUSCH data/DM-RS energy
        % accounting while leaving the DL noise primitive unchanged.
        [rxWaveform, noiseInfo] = ...
            sixgr.conformance.addPUSCHReferenceNoise( ...
            channelWaveform, carrier, tx.PUSCH, snr_dB, ...
            "DMRSPowerScale", double(tx.DMRSPowerScale), ...
            "Seed", noiseSeed);
        configuredNoiseVarianceSource = ...
            "sixgr.conformance.addPUSCHReferenceNoise_ts38104_slot_energy_contract";
    end

    rxArgs = { ...
        "Carrier", carrier, ...
        "TransportBlockSize", double(entry.coding.tbs_bits), ...
        "TargetCodeRate", propagation.TargetCodeRate, ...
        "RV", rv, ...
        "NoiseVar", double(noiseInfo.SampleNoiseVariance), ...
        "NoiseVarDomain", "time", ...
        "HARQSoftBufferLLR", softBuffer, ...
        "HARQSoftBufferLayout", softLayout, ...
        "CodingLayout", tx.CodingLayout, ...
        "CompactOutput", true, ...
        "FastAWGNPath", false, ...
        "SkipTimingEstimate", propagation.SkipTimingEstimate};
    if ~isempty(opt.MaxDecoderIterations)
        rxArgs = [rxArgs, {"MaxIterations", double(opt.MaxDecoderIterations)}]; %#ok<AGROW>
    end

    if string(entry.direction) == "downlink"
        [rx, rxInfo] = sixgr.phy.dl.PDSCH_Rx(rxWaveform, cfg, ...
            rxArgs{:}, ...
            "PDSCH", tx.PDSCH, ...
            "PDSCHIndices", tx.PDSCHIndices, ...
            "CodingPlan", tx.CodingPlans, ...
            "CalibrationReceiverBundle", sixgr.util.structGet( ...
                txInfo,"CalibrationReceiverBundle",struct()), ...
            "ExecutionProfile", "phy_calibration", ...
            "PrecodingMatrix", txPrecoder);
    else
        [rx, rxInfo] = sixgr.phy.ul.PUSCH_Rx(rxWaveform, cfg, ...
            rxArgs{:}, ...
            "PUSCH", tx.PUSCH, ...
            "PUSCHIndices", tx.PUSCHIndices, ...
            "ConfiguredNoiseVariance", double(noiseInfo.SampleNoiseVariance), ...
            "ConfiguredNoiseVarianceSource", ...
                configuredNoiseVarianceSource, ...
            "StrictNoiseVarianceRequired", true);
    end
    localAssertTruthReceiver(entry, tx, rx);

    evidence.Noise = noiseInfo;
    evidence.Tx = localCompactTxEvidence(tx, txInfo);
    evidence.Rx = localCompactRxEvidence(rx, rxInfo);
    evidence.AttemptTx{end + 1, 1} = evidence.Tx;
    evidence.AttemptRx{end + 1, 1} = evidence.Rx;
    evidence.Timing = localFinalizeHARQTimingEvidence( ...
        timing, absoluteSlotByAttempt(1:attempts), ...
        channelStartSampleByAttempt(1:attempts), ...
        advanceSamplesByAttempt(1:attempts));
    if logical(rx.Ok)
        delivered = true;
        return;
    end
    softBuffer = rx.HARQSoftBuffer;
    softLayout = tx.CodingLayout;
end
end

function timing = localAlignDLTimelineToStandardFrame( ...
        timing, transportBlockIndex, numAttempts)
% Every independently sampled DL transport block owns one complete 20-slot
% TS 38.101-4 period. Retransmissions retain the configured opportunity
% spacing inside that continuously propagated period.
if numAttempts == 0
    return;
end
spacing = double(timing.RetransmissionSpacingSlots);
relativeSlots = 1 + (0:numAttempts-1).' .* spacing;
if any(relativeSlots > 19)
    error("sixgr:conformance:FRCHARQDoesNotFitStandardPeriod", ...
        ["The configured DL HARQ attempt spacing places a retransmission " ...
         "outside the 19 PDSCH slots of one 20-slot FRC period."]);
end
periodBase = (double(transportBlockIndex) - 1) * 20;
timing.TimelineScope = "independent_tb_complete_20_slot_frc_period";
timing.FirstOpportunityIndex = periodBase + 1;
timing.OpportunityIndexByAttempt = uint64(periodBase + relativeSlots);
timing.AbsoluteSlotByAttempt = uint64(periodBase + relativeSlots);
timing.InactiveSlotWaveform = "complete_standard_frc_slot_waveform";
timing.ChannelEvolutionBetweenRetransmissionsMaterialized = true;
end

function frame = localBuildStatisticalDownlinkFrame( ...
        entry, carrierTemplate, propagation, cfg, tbBits, timing, ...
        rvSequence, transmissionsBeforeTB, opt)
template = propagation.StandardDownlinkFrameTemplate;
if ~(isstruct(template) && isfield(template, "FrameGrid") && ...
        isfield(template, "PDSCHGrids"))
    error("sixgr:conformance:StandardDLFrameTemplateUnavailable", ...
        "Statistical DL execution requires the materialized 20-slot FRC template.");
end
periodSlots = double(template.PeriodSlots);
symbolsPerSlot = double(template.SymbolsPerSlot);
samplesPerSlot = double(template.SamplesPerSlot);
frameGrid = template.FrameGrid;
attemptCount = numel(rvSequence);
attemptTx = cell(attemptCount,1);
attemptTxInfo = cell(attemptCount,1);
attemptPrecoder = cell(attemptCount,1);
targetSlot = zeros(attemptCount,1);
targetOffset = zeros(attemptCount,1);
seen = false(periodSlots,1);

for rvIndex = 1:attemptCount
    absoluteSlot = double(timing.AbsoluteSlotByAttempt(rvIndex));
    slot = mod(absoluteSlot, periodSlots);
    if slot == double(entry.standard_downlink_timeline.ssb_pbch.slot)
        error("sixgr:conformance:FRCHARQCollidesWithSSBSlot", ...
            "A DL HARQ attempt was assigned to SS/PBCH slot %d.", slot);
    end
    if seen(slot+1)
        error("sixgr:conformance:DuplicateFRCHARQSlot", ...
            "Two DL HARQ attempts were assigned to slot %d of one period.", slot);
    end
    seen(slot+1) = true;
    carrier = localCloneCarrier(carrierTemplate);
    carrier = localSetCarrierAbsoluteSlot(carrier, absoluteSlot);
    pdsch = localConfigurePDSCHForSlot( ...
        entry, carrier, propagation.PhysicalChannel);
    % This is the same catalog-seeded per-slot Type-I page used to create
    % the filler waveform. Replacing the filler therefore changes only the
    % scheduled codeword/DM-RS, not the slot's precoder contract.
    slotPrecoder = localPDSCHPrecoderForSlot( ...
        entry, carrier, cfg, double(opt.Seed) + slot + 104729);
    [tx, txInfo] = sixgr.phy.dl.PDSCH_Tx(cfg, ...
        "Carrier", carrier, "PDSCH", pdsch, ...
        "TransportBlockBits", tbBits, ...
        "TransportBlockSizeOverride", double(entry.coding.tbs_bits), ...
        "RV", double(rvSequence(rvIndex)), ...
        "TargetCodeRate", propagation.TargetCodeRate, "XOverhead", 0, ...
        "NumTxAnt", double(entry.mimo.tx_antennas), ...
        "PrecodingMatrix", slotPrecoder, ...
        "ExecutionProfile", "phy_calibration", "CompactOutput", false);
    if localIsDLTrackingSlot(entry, absoluteSlot)
        tx = localMaterializeTrackingCSIRS(entry, carrier, tx);
    end
    localAssertExactTx(entry, tx, transmissionsBeforeTB + rvIndex);

    columns = slot*symbolsPerSlot + (1:symbolsPerSlot);
    fillerData = template.PDSCHGrids{slot+1};
    residual = frameGrid(:,columns,:) - fillerData;
    if any(abs(residual) > 1e-12 & abs(tx.Grid) > 1e-12, "all")
        error("sixgr:conformance:StandardDLTrialReplacementCollision", ...
            "The trial PDSCH collides with a non-PDSCH signal in slot %d.", slot);
    end
    frameGrid(:,columns,:) = residual + tx.Grid;
    tx.StandardDownlinkAuxiliary = template.AuxiliaryEvidence{slot+1};
    tx.StandardFrameExecution = struct( ...
        "Materialized", true, ...
        "PeriodSlots", periodSlots, ...
        "TargetSlotWithinPeriod", slot, ...
        "TargetAbsoluteSlot", absoluteSlot, ...
        "TargetSampleOffset", slot*samplesPerSlot, ...
        "NoProxyOrFallbackUsed", true);
    attemptTx{rvIndex} = tx;
    attemptTxInfo{rvIndex} = txInfo;
    attemptPrecoder{rvIndex} = slotPrecoder;
    targetSlot(rvIndex) = slot;
    targetOffset(rvIndex) = slot*samplesPerSlot;
end

[waveform, ofdmInfo] = sixgr.phy.waveform.ofdmModulate( ...
    carrierTemplate, frameGrid, "Windowing", 0);
if size(waveform,1) ~= periodSlots*samplesPerSlot
    error("sixgr:conformance:StatisticalDLFrameLengthMismatch", ...
        "Statistical FRC frame has %d samples; expected %d.", ...
        size(waveform,1), periodSlots*samplesPerSlot);
end
frame = struct( ...
    "ContractVersion", "sixgr_ts38101_4_statistical_dl_frame/v1", ...
    "Waveform", waveform, ...
    "AttemptTx", {attemptTx}, ...
    "AttemptTxInfo", {attemptTxInfo}, ...
    "AttemptPrecoder", {attemptPrecoder}, ...
    "TargetSlotWithinPeriod", targetSlot, ...
    "TargetSampleOffset", targetOffset, ...
    "SamplesPerSlot", samplesPerSlot, ...
    "PeriodSlots", periodSlots, ...
    "Evidence", struct( ...
        "Materialized", true, ...
        "StandardReference", string( ...
            entry.standard_downlink_timeline.standard_reference), ...
