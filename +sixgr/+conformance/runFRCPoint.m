        string(sixgr.util.structGet(state, "SchemaVersion", "")) ~= ...
        "sixgr.conformance.frc_point_progress/v2"
    error("sixgr:conformance:FRCPointProgressInvalid", ...
        "FRC point checkpoint '%s' is missing or has invalid field(s): %s.", ...
        progress.CheckpointPath, strjoin(missing, ", "));
end
if lower(string(state.IdentitySHA256)) ~= ...
        lower(string(progress.IdentitySHA256))
    error("sixgr:conformance:FRCPointProgressIdentityMismatch", ...
        ("FRC point checkpoint '%s' belongs to a different catalog, " + ...
        "source, SNR, seed, receiver, or sampling policy."), ...
        progress.CheckpointPath);
end
numTB = double(state.CompletedTransportBlocks);
maxTB = double(opt.MaxTransportBlocks);
maxHARQ = double(entry.harq.max_transmissions);
validIdentity = string(state.EntryId) == string(entry.id) && ...
    string(state.ConditionId) == string(entry.condition.id) && ...
    double(state.ExperimentSeed) == double(opt.Seed) && ...
    double(state.SNR_dB) == double(snr_dB) && ...
    double(state.SNRSeedIndex) == double(snrIndex);
validCounts = isfinite(numTB) && numTB == fix(numTB) && ...
    numTB >= 0 && numTB <= maxTB && ...
    numel(state.Delivered) == numTB && ...
    numel(state.Attempts) == numTB && ...
    numel(state.FirstTransmissionIndex) == numTB && ...
    numel(state.FadingChannelSeed) == numTB && ...
    numel(state.HARQProcessID) == numTB && ...
    isequal(size(state.NoiseSeedByAttempt), [numTB maxHARQ]) && ...
    isequal(size(state.RVByAttempt), [numTB maxHARQ]) && ...
    isequal(size(state.AbsoluteSlotByAttempt), [numTB maxHARQ]) && ...
    isequal(size(state.ChannelStartSampleByAttempt), [numTB maxHARQ]);
attempts = double(state.Attempts(:));
delivered = logical(state.Delivered(:));
validTotals = all(isfinite(attempts)) && ...
    all(attempts == fix(attempts)) && ...
    all(attempts >= 1 & attempts <= maxHARQ) && ...
    double(state.DeliveredTransportBlocks) == nnz(delivered) && ...
    double(state.FailedTransportBlocks) == nnz(~delivered) && ...
    double(state.Transmissions) == sum(attempts);
if ~validIdentity || ~validCounts || ~validTotals
    error("sixgr:conformance:FRCPointProgressInvalid", ...
        ("FRC point checkpoint '%s' failed its identity, dimension, " + ...
        "attempt, or aggregate-count integrity checks."), ...
        progress.CheckpointPath);
end
end

