function timing = localAlignULTimelineToStandardWaveform( ...
        timing, transportBlockIndex, numAttempts)
if numAttempts == 0
    return;
end
spacing = double(timing.RetransmissionSpacingSlots);
relativeSlots = (0:numAttempts-1).' .* spacing;
spanSlots = 1 + (numAttempts-1)*spacing;
clusterBase = (double(transportBlockIndex)-1)*spanSlots;
timing.TimelineScope = "independent_tb_continuous_pusch_frc_waveform";
timing.FirstOpportunityIndex = clusterBase + 1;
timing.OpportunityIndexByAttempt = uint64(clusterBase + relativeSlots + 1);
timing.AbsoluteSlotByAttempt = uint64(clusterBase + relativeSlots);
timing.InactiveSlotWaveform = "full_slot_pusch_frc_filler";
timing.ChannelEvolutionBetweenRetransmissionsMaterialized = true;
end

function frame = localBuildStatisticalUplinkWaveform( ...
        entry, carrierTemplate, propagation, cfg, tbBits, timing, ...
        rvSequence, transmissionsBeforeTB)
template = propagation.StandardUplinkWaveformTemplate;
if ~(isstruct(template) && isfield(template, "FrameGrid") && ...
        isfield(template, "PUSCHGrids"))
    error("sixgr:conformance:StandardULWaveformTemplateUnavailable", ...
        "Statistical UL execution requires the materialized PUSCH FRC template.");
end
spanSlots = double(template.SpanSlots);
symbolsPerSlot = double(template.SymbolsPerSlot);
samplesPerSlot = double(template.SamplesPerSlot);
frameGrid = template.FrameGrid;
attemptCount = numel(rvSequence);
attemptTx = cell(attemptCount,1);
attemptTxInfo = cell(attemptCount,1);
targetSlot = zeros(attemptCount,1);
targetOffset = zeros(attemptCount,1);
seen = false(spanSlots,1);
clusterBase = double(timing.AbsoluteSlotByAttempt(1));
for rvIndex = 1:attemptCount
    absoluteSlot = double(timing.AbsoluteSlotByAttempt(rvIndex));
    slot = absoluteSlot-clusterBase;
    if slot < 0 || slot >= spanSlots || slot ~= fix(slot)
        error("sixgr:conformance:ULHARQOutsideStandardWaveform", ...
            "UL HARQ slot %d is outside its %d-slot FRC waveform.", ...
            absoluteSlot, spanSlots);
    end
    if seen(slot+1)
        error("sixgr:conformance:DuplicateULFRCHARQSlot", ...
            "Two UL HARQ attempts were assigned to FRC slot %d.", slot);
    end
    seen(slot+1) = true;
    carrier = localCloneCarrier(carrierTemplate);
    carrier = localSetCarrierAbsoluteSlot(carrier, absoluteSlot);
    [tx, txInfo] = sixgr.phy.ul.PUSCH_Tx(cfg, ...
        "Carrier", carrier, "PUSCH", propagation.PhysicalChannel, ...
        "TransportBlockBits", tbBits, ...
        "TransportBlockSizeOverride", double(entry.coding.tbs_bits), ...
        "RV", double(rvSequence(rvIndex)), ...
        "TargetCodeRate", propagation.TargetCodeRate, "XOverhead", 0, ...
        "NumTxAnt", double(entry.mimo.tx_antennas), "CompactOutput", false);
    localAssertExactTx(entry, tx, transmissionsBeforeTB+rvIndex);
    columns = slot*symbolsPerSlot + (1:symbolsPerSlot);
    filler = template.PUSCHGrids{slot+1};
    residual = frameGrid(:,columns,:) - filler;
    if any(abs(residual) > 1e-12, "all")
        error("sixgr:conformance:StandardULTrialReplacementResidual", ...
            "UL FRC slot %d contains a non-PUSCH residual.", slot);
    end
    frameGrid(:,columns,:) = tx.Grid;
    tx.StandardUplinkWaveform = struct( ...
        "Materialized", true, "ContinuousSlotCount", spanSlots, ...
        "TargetSlotWithinWaveform", slot, ...
        "TargetAbsoluteSlot", absoluteSlot, ...
        "TargetSampleOffset", slot*samplesPerSlot, ...
        "NoProxyOrFallbackUsed", true);
    attemptTx{rvIndex} = tx;
    attemptTxInfo{rvIndex} = txInfo;
    targetSlot(rvIndex) = slot;
    targetOffset(rvIndex) = slot*samplesPerSlot;
end
[waveform, ofdmInfo] = sixgr.phy.waveform.ofdmModulate( ...
    carrierTemplate, frameGrid, "Windowing", 0);
if size(waveform,1) ~= spanSlots*samplesPerSlot
    error("sixgr:conformance:StatisticalULWaveformLengthMismatch", ...
        "Statistical UL FRC waveform has %d samples; expected %d.", ...
        size(waveform,1), spanSlots*samplesPerSlot);
end
frame = struct( ...
    "ContractVersion", "sixgr_ts38104_statistical_ul_waveform/v1", ...
    "Waveform", waveform, "AttemptTx", {attemptTx}, ...
    "AttemptTxInfo", {attemptTxInfo}, ...
    "TargetSlotWithinWaveform", targetSlot, ...
    "TargetSampleOffset", targetOffset, ...
    "SamplesPerSlot", samplesPerSlot, "SpanSlots", spanSlots, ...
    "Evidence", struct( ...
        "Materialized", true, ...
        "StandardReference", string(template.Evidence.StandardReference), ...
        "TargetSlotWithinWaveform", targetSlot, ...
        "TargetAbsoluteSlot", double(timing.AbsoluteSlotByAttempt(:)), ...
        "RVSequence", double(rvSequence(:)), ...
        "FrameGridSHA256", string( ...
            sixgr.phy.waveform.WaveformHash.numeric(frameGrid)), ...
        "FrameWaveformSHA256", string( ...
            sixgr.phy.waveform.WaveformHash.numeric(waveform)), ...
        "FrameGridSize", double(size(frameGrid)), ...
        "WaveformSize", double(size(waveform)), ...
        "SampleRate_Hz", double(ofdmInfo.SampleRate), ...
        "NoProxyOrFallbackUsed", true));
end

