function contract = localCorrelationContract(entry)
requested = strtrim(string(entry.mimo.correlation_matrix));
normalized = upper(regexprep(requested, "[\s_-]+", " "));
direction = string(entry.direction);
kind = string(entry.condition.kind);
nTx = double(entry.mimo.tx_antennas);
nRx = double(entry.mimo.rx_antennas);

contract = struct( ...
    "Requested", requested, ...
    "Exact", false, ...
    "Blocker", "unsupported_mimo_correlation_contract", ...
    "Backend", "", ...
    "ToolboxMIMOCorrelation", "", ...
    "TransmissionDirection", localTitleDirection(direction), ...
    "ExpectedSpatialCorrelationMatrix", zeros(0, 0), ...
    "StandardReference", "");

if kind == "awgn"
    supportedDimensions = (nTx == 1 && nRx == 2) || ...
        (nTx == 2 && nRx == 2) || (nTx == 4 && nRx == 4);
    if normalized == "STATIC CHANNEL ANNEX B 1"
        exact = direction == "downlink" && nTx == 1 && nRx == 2 && ...
            contains(upper(string(entry.condition.static_channel_reference)), ...
            "ANNEX B.1");
        backend = "ts38101_4_annex_b1_static_matrix";
    elseif normalized == "NOT APPLICABLE AWGN"
        exact = supportedDimensions && ...
            string(entry.condition.static_channel_reference) == "not_applicable";
        backend = "deterministic_awgn_static_mimo_matrix";
    else
        exact = false;
        backend = "";
    end
    contract.Exact = logical(exact);
    contract.Backend = backend;
    contract.StandardReference = string(entry.condition.static_channel_reference);
    if exact
        contract.Blocker = "";
    else
        contract.Blocker = "unsupported_awgn_static_channel_contract";
    end
    return;
end

if direction == "downlink" && normalized == "ULA LOW" && ...
        ((nTx == 2 && nRx == 2) || (nTx == 4 && nRx == 4))
    toolboxToken = "Low";
    expected = eye(nTx * nRx);
    standardReference = "TS_38_101_4_B.2.3.1.2_low";
elseif direction == "downlink" && normalized == "ULA MEDIUM" && ...
        nTx == 2 && nRx == 2
    toolboxToken = "Medium";
    expected = [ ...
        1, 0.9, 0.3, 0.27; ...
        0.9, 1, 0.27, 0.3; ...
        0.3, 0.27, 1, 0.9; ...
        0.27, 0.3, 0.9, 1];
    standardReference = "TS_38_101_4_B.2.3.1.2_medium";
elseif direction == "uplink" && normalized == "LOW" && ...
        nTx == 1 && nRx == 2
    toolboxToken = "Low";
    expected = eye(nTx * nRx);
    standardReference = "TS_38_104_G.2.3_low";
else
    return;
end

contract.Exact = true;
contract.Blocker = "";
contract.Backend = "nrTDLChannel_predefined_spatial_correlation";
contract.ToolboxMIMOCorrelation = toolboxToken;
contract.ExpectedSpatialCorrelationMatrix = expected;
contract.StandardReference = standardReference;
end

