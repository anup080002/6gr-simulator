function state = localValidatePointProgressCheckpoint( ...
        state, progress, entry, snr_dB, snrIndex, opt)
required = ["SchemaVersion","IdentitySHA256","Identity", ...
    "EntryId","ConditionId","SNR_dB","SNRSeedIndex", ...
    "ExperimentSeed", ...
    "CompletedTransportBlocks","DeliveredTransportBlocks", ...
    "FailedTransportBlocks","Transmissions","Completed", ...
    "StopReason","BitStreamState","Delivered","Attempts", ...
    "FirstTransmissionIndex","FadingChannelSeed", ...
    "NoiseSeedByAttempt","RVByAttempt","AbsoluteSlotByAttempt", ...
    "ChannelStartSampleByAttempt","HARQProcessID","Noise", ...
    "LastReceiver","FirstTransmission", ...
    "LastTransportBlockAttemptTx","LastTransportBlockAttemptRx", ...
    "Propagation"];
