function pdsch = localConfigurePDSCHForSlot(entry, carrier, pdsch)
if string(entry.direction) ~= "downlink"
    return;
end
if ~isprop(pdsch, "ReservedRE")
    error("sixgr:conformance:PDSCHReservedREUnsupported", ...
        "Exact DL FRC execution requires nrPDSCHConfig.ReservedRE support.");
end
pdsch.ReservedRE = [];
if ~localIsDLTrackingSlot(entry, localCarrierAbsoluteSlot(carrier))
    return;
end
[indices, ~, ~] = localTrackingCSIRSResources(entry, carrier);
% nrPDSCHConfig.ReservedRE is zero-based within the BWP, while
% nrCSIRSIndices returns one-based linear grid indices by default.
pdsch.ReservedRE = unique(double(indices(:)) - 1, "stable");
if numel(pdsch.ReservedRE) ~= 312
    error("sixgr:conformance:TrackingCSIRSReservationMismatch", ...
        ("DL FRC tracking slots require exactly 312 reserved PDSCH RE for " + ...
        "the two density-three CSI-RS resources; got %d."), ...
        numel(pdsch.ReservedRE));
end
end

function W = localPDSCHPrecoderForSlot(entry, carrier, cfg, seed)
nTx = double(entry.mimo.tx_antennas);
nLayers = double(entry.mimo.layers);
if nTx == 1 && nLayers == 1
    W = [];
    return;
end
if ~isfield(entry.allocation, "prb_bundling_size")
    error("sixgr:conformance:MissingPRBBundlingSize", ...
        "DL FRC %s does not encode its PRB bundling size.", ...
        string(entry.frc_id));
end
prgSize = double(entry.allocation.prb_bundling_size);
prgInfo = nrPRGInfo(carrier, prgSize);
cfg.phy.csi.codebookType = "type1";
cfg.phy.csi.pmiCodebookMode = "type1_su_mimo";
[candidates, ~] = sixgr.phy.dl.pmiCodebookCandidates( ...
    cfg, nLayers, nTx, "Mode", "type1_su_mimo");
if isempty(candidates)
    error("sixgr:conformance:EmptyTypeIPrecoderCodebook", ...
        "No applicable single-panel Type-I precoders exist for %d Tx ports and rank %d.", ...
        nTx, nLayers);
end
stream = RandStream("mt19937ar", "Seed", localFoldSeed(seed));
selection = randi(stream, numel(candidates), [1, double(prgInfo.NPRG)]);
W = complex(zeros(nTx, nLayers, double(prgInfo.NPRG)));
for prg = 1:double(prgInfo.NPRG)
    page = double(candidates(selection(prg)).W);
    if ~isequal(size(page), [nTx, nLayers])
        error("sixgr:conformance:TypeIPrecoderShapeMismatch", ...
            "Type-I precoder page has shape %s; expected [%d %d].", ...
            mat2str(size(page)), nTx, nLayers);
    end
    % The shared PHY codebook exposes unit-norm columns (trace=NumLayers).
    % For the TS 38.101-4 conducted reference, preserve one unit of total
    % pre-precoding RE power independently of rank.
    page = page ./ sqrt(nLayers);
    pageTrace = real(trace(page * page'));
    if ~(isfinite(pageTrace) && abs(pageTrace - 1) <= 1e-12)
        error("sixgr:conformance:TypeIPrecoderPowerNormalization", ...
            ("FRC Type-I PRG page %d has trace(W*W')=%.16g after " + ...
            "rank normalization; expected exactly one."), prg, pageTrace);
    end
    W(:, :, prg) = page;
end
end

function tx = localMaterializeTrackingCSIRS(entry, carrier, tx)
if ~localIsDLTrackingSlot(entry, localCarrierAbsoluteSlot(carrier))
    return;
end
if ~isfield(tx, "Grid") || isempty(tx.Grid)
    error("sixgr:conformance:TrackingCSIRSGridUnavailable", ...
        "Tracking-slot PDSCH Tx must retain its resource grid.");
end
[indices, symbols, resources] = localTrackingCSIRSResources(entry, carrier);
reserved = unique(double(tx.PDSCH.ReservedRE(:)) + 1, "stable");
actual = unique(double(indices(:)), "stable");
if ~isequal(reserved, actual)
    error("sixgr:conformance:TrackingCSIRSReservationMappingMismatch", ...
        "Materialized tracking CSI-RS indices do not equal PDSCH.ReservedRE.");
end
if any(abs(tx.Grid(actual)) > 1e-12)
    error("sixgr:conformance:TrackingCSIRSCollision", ...
        "Tracking CSI-RS resources collide with an already mapped signal.");
end
tx.Grid(actual) = symbols(:);
[waveform, ofdmInfo] = sixgr.phy.waveform.ofdmModulate( ...
    carrier, tx.Grid, "Windowing", double(tx.OFDMWindowingSamples));
tx.Waveform = waveform;
tx.OFDMInfo = ofdmInfo;
tx.OFDM = ofdmInfo;
tx.TrackingCSIRS = struct( ...
    "ContractVersion", "TS38101_4_Table5_2_1_tracking_csirs/v1", ...
    "Materialized", true, ...
    "Slot", double(localCarrierAbsoluteSlot(carrier)), ...
    "Frame", double(carrier.NFrame), ...
    "SlotWithinFrame", double(carrier.NSlot), ...
    "ResourceCount", numel(resources), ...
    "NRE", double(numel(actual)), ...
    "Indices", actual, ...
    "Symbols", symbols(:), ...
    "Resources", {resources}, ...
    "EPREScale", 1, ...
    "Source", "nrCSIRS_exact_table_5_2_1_resources");
end

function [indices, symbols, resources] = localTrackingCSIRSResources(entry, carrier)
absoluteSlot = localCarrierAbsoluteSlot(carrier);
if ~localIsDLTrackingSlot(entry, absoluteSlot)
    indices = zeros(0, 1);
    symbols = complex(zeros(0, 1));
    resources = {};
    return;
end
slotOffset = mod(double(absoluteSlot), 20);
symbolLocations = [6, 10];
resources = cell(1, numel(symbolLocations));
indexCell = cell(1, numel(symbolLocations));
symbolCell = cell(1, numel(symbolLocations));
for resourceIndex = 1:numel(symbolLocations)
    csirs = nrCSIRSConfig;
    csirs.CSIRSType = "nzp";
    csirs.RowNumber = 1;
    csirs.Density = "three";
    csirs.SubcarrierLocations = 0;
    csirs.SymbolLocations = symbolLocations(resourceIndex);
    csirs.RBOffset = double(entry.carrier.prb_start);
    csirs.NumRB = double(entry.carrier.n_prb);
    csirs.NID = 0;
    csirs.CSIRSPeriod = [20, slotOffset];
    indexCell{resourceIndex} = double(nrCSIRSIndices(carrier, csirs));
    symbolCell{resourceIndex} = nrCSIRS(carrier, csirs);
    resources{resourceIndex} = csirs;
end
indices = vertcat(indexCell{:});
symbols = vertcat(symbolCell{:});
if numel(indices) ~= numel(symbols)
    error("sixgr:conformance:TrackingCSIRSIndexSymbolMismatch", ...
        "Tracking CSI-RS index count %d differs from symbol count %d.", ...
        numel(indices), numel(symbols));
end
end

function tf = localIsDLTrackingSlot(entry, slot)
tf = string(entry.direction) == "downlink" && ...
    any(mod(double(slot), 20) == ...
    double(entry.coding.tracking_slot_indices(:).'));
end

function propagation = localCreatePropagation(entry, carrier, execution, seed)
ofdm = nrOFDMInfo(carrier);
propagation = struct();
propagation.Kind = string(entry.condition.kind);
propagation.Model = string(entry.condition.model);
propagation.SampleRate_Hz = double(ofdm.SampleRate);
propagation.Object = [];
propagation.ChannelInfo = struct();
propagation.FilterPad_samples = 0;
propagation.SamplesProcessed = uint64(0);
propagation.SkipTimingEstimate = propagation.Kind == "awgn";
propagation.NumTxAntennas = double(entry.mimo.tx_antennas);
propagation.NumRxAntennas = double(entry.mimo.rx_antennas);
propagation.PhysicalChannel = execution.PhysicalChannel;
propagation.TargetCodeRate = double(execution.TargetCodeRate);
propagation.Cfg = execution.Cfg;
propagation.ChannelSeed = localFoldSeed(seed);
propagation.CorrelationContract = localCorrelationContract(entry);

if propagation.Kind == "fading"
    correlation = propagation.CorrelationContract;
    if ~logical(correlation.Exact)
        error("sixgr:conformance:UnsupportedTDLCorrelationExecution", ...
            ("FRC %s requests MIMO correlation '%s', which the truth " + ...
            "runner cannot reproduce exactly (%s)."), ...
            string(entry.frc_id), string(correlation.Requested), ...
            string(correlation.Blocker));
    end
    channel = nrTDLChannel;
    channel.DelayProfile = char(string(entry.condition.model));
    channel.DelaySpread = double(entry.condition.delay_spread_ns) * 1e-9;
    channel.MaximumDopplerShift = double(entry.condition.max_doppler_hz);
    channel.SampleRate = propagation.SampleRate_Hz;
    channel.NumTransmitAntennas = double(entry.mimo.tx_antennas);
    channel.NumReceiveAntennas = double(entry.mimo.rx_antennas);
    if ~isprop(channel, "MIMOCorrelation") || ...
            ~isprop(channel, "TransmissionDirection")
        error("sixgr:conformance:TDLCorrelationPropertiesUnavailable", ...
            ("Exact FRC fading execution requires nrTDLChannel " + ...
            "MIMOCorrelation and TransmissionDirection properties."));
    end
    channel.MIMOCorrelation = char(correlation.ToolboxMIMOCorrelation);
    channel.TransmissionDirection = char(correlation.TransmissionDirection);
    if isprop(channel, "NormalizePathGains")
        channel.NormalizePathGains = true;
    end
    if isprop(channel, "NormalizeChannelOutputs")
        % Conducted FRC SNR is formed from signal and noise power summed
        % across the receive connectors. nrTDLChannel's output
        % normalization divides the aggregate signal power by NRx, while
        % the independently injected connector noise is not divided. Keep
        % normalized path gains, but preserve the per-connector channel
        % power so the requested Es/N0 is not shifted by -10*log10(NRx).
        channel.NormalizeChannelOutputs = false;
    end
    if isprop(channel, "RandomStream")
        channel.RandomStream = "mt19937ar with seed";
    end
    if isprop(channel, "Seed")
        channel.Seed = localFoldSeed(seed);
    end
    reset(channel);
    channelInfo = info(channel);
    localAssertTDLCorrelationMatrix(entry, correlation, channelInfo);
    propagation.Object = channel;
    propagation.ChannelInfo = channelInfo;
    propagation.FilterPad_samples = localChannelPadSamples( ...
        channelInfo, propagation.SampleRate_Hz, ...
        double(entry.condition.delay_spread_ns) * 1e-9);
    propagation.SkipTimingEstimate = false;
end
end

function [rxWaveform, propagation] = localApplyPropagation(txWaveform, propagation)
if propagation.Kind == "awgn"
    nTx = size(txWaveform, 2);
    nRx = double(propagation.NumRxAntennas);
    if nTx ~= double(propagation.NumTxAntennas)
        error("sixgr:conformance:TruthWaveformAntennaMismatch", ...
            "Truth Tx produced %d waveform column(s); the FRC requires %d.", ...
            nTx, round(double(propagation.NumTxAntennas)));
    end
    if nTx == 1 && nRx == 2
        H = ones(2, 1);
    elseif nTx == 2 && nRx == 2
        H = [1, 1j; 1, -1j];
    elseif nTx == 4 && nRx == 4
        H = [ ...
            1,  1,  1j,  1j; ...
            1,  1, -1j, -1j; ...
            1, -1,  1j, -1j; ...
            1, -1, -1j,  1j];
    else
        error("sixgr:conformance:UnsupportedStaticChannelDimensions", ...
            ("The Annex-B.1 static channel supports 1x2, 2x2, and 4x4, " + ...
            "got %dx%d."), nTx, nRx);
    end
    rxWaveform = txWaveform * transpose(H);
    propagation.SamplesProcessed = propagation.SamplesProcessed + ...
        uint64(size(txWaveform, 1));
    return;
end

pad = zeros(double(propagation.FilterPad_samples), size(txWaveform, 2), ...
    "like", txWaveform);
channelInput = [txWaveform; pad];
try
    rxWaveform = propagation.Object(channelInput);
    propagation.SamplesProcessed = propagation.SamplesProcessed + ...
        uint64(size(channelInput, 1));
catch cause
    failure = MException("sixgr:conformance:FadingChannelExecutionFailed", ...
        "The concrete %s truth channel failed.", propagation.Model);
    failure = addCause(failure, cause);
    throw(failure);
end
end

function [propagation, advanceSamples] = localAdvancePropagationToSlot( ...
        propagation, slotSamples, slotGap)
slotSamples = double(slotSamples);
slotGap = double(slotGap);
if ~(isscalar(slotSamples) && isfinite(slotSamples) && ...
        slotSamples > 0 && slotSamples == fix(slotSamples))
    error("sixgr:conformance:InvalidHARQSlotSampleCount", ...
        "HARQ channel advancement requires a positive integer slot length.");
end
if ~(isscalar(slotGap) && isfinite(slotGap) && ...
        slotGap >= 1 && slotGap == fix(slotGap))
    error("sixgr:conformance:InvalidHARQSlotGap", ...
        "HARQ retransmission slot gap must be a positive integer.");
end
if propagation.Kind == "awgn"
    advanceSamples = max(0, slotGap * slotSamples - slotSamples);
    propagation.SamplesProcessed = propagation.SamplesProcessed + ...
        uint64(advanceSamples);
    return;
end

alreadyConsumedAfterSlotStart = slotSamples + ...
    double(propagation.FilterPad_samples);
advanceSamples = slotGap * slotSamples - alreadyConsumedAfterSlotStart;
if advanceSamples < 0 || advanceSamples ~= fix(advanceSamples)
    error("sixgr:conformance:HARQChannelTimelineOverlap", ...
        ["The fading channel already consumed %d samples after the prior " ...
        "slot start, but the next HARQ opportunity is only %d slot(s) " ...
        "(%d samples) later."], alreadyConsumedAfterSlotStart, ...
        slotGap, slotGap * slotSamples);
end
if advanceSamples == 0
    return;
end
idle = zeros(advanceSamples, double(propagation.NumTxAntennas));
try
    propagation.Object(idle);
catch cause
    failure = MException("sixgr:conformance:FadingChannelAdvanceFailed", ...
        "The concrete %s channel failed while advancing the HARQ timeline.", ...
        propagation.Model);
    failure = addCause(failure, cause);
    throw(failure);
end
propagation.SamplesProcessed = propagation.SamplesProcessed + ...
    uint64(advanceSamples);
end

function waveform = localApplyCFO(waveform, sampleRate_Hz, ...
        frequencyOffset_Hz, startSample)
if nargin < 4
    startSample = 0;
end
if abs(double(frequencyOffset_Hz)) <= 0
    return;
end
if ~(isfinite(sampleRate_Hz) && sampleRate_Hz > 0)
    error("sixgr:conformance:MissingSampleRateForCFO", ...
        "A finite positive sample rate is required to apply the FRC frequency offset.");
end
n = double(startSample) + (0:size(waveform, 1)-1).';
rotation = exp(1j * 2 * pi * double(frequencyOffset_Hz) / ...
    double(sampleRate_Hz) .* n);
waveform = waveform .* cast(rotation, "like", waveform);
end

function localAssertExactTx(entry, tx, transmissionIndex)
expectedTBS = double(entry.coding.tbs_bits);
actualTBS = double(tx.TransportBlockSize);
if ~(isscalar(actualTBS) && actualTBS == expectedTBS)
    error("sixgr:conformance:TransportBlockSizeMismatch", ...
        "FRC %s requires TBS=%d bits, but the truth Tx produced %s.", ...
        string(entry.frc_id), expectedTBS, mat2str(actualTBS));
end
scheduledTBS = double(tx.ScheduledTransportBlockSize);
isTrackingSlot = string(entry.direction) == "downlink" && ...
    localIsDLTrackingSlot(entry, localCarrierAbsoluteSlot(tx.Carrier));
if ~isTrackingSlot && ~(isscalar(scheduledTBS) && scheduledTBS == expectedTBS)
    error("sixgr:conformance:ScheduledTransportBlockSizeMismatch", ...
        ("FRC %s requires allocation-derived TBS=%d bits, but the truth Tx " + ...
        "scheduled %s bits."), string(entry.frc_id), expectedTBS, ...
        mat2str(scheduledTBS));
end
if isTrackingSlot
    source = string(tx.TransportBlockSizeSource);
    if source ~= "harq_replay_stored_transport_block"
        error("sixgr:conformance:TrackingSlotTBSOwnershipMismatch", ...
            ("FRC %s tracking slot must preserve the Annex-A fixed TBS " + ...
            "through stored-HARQ replay ownership; source was '%s'."), ...
            string(entry.frc_id), source);
    end
end

if string(entry.direction) == "uplink"
    if ~isfield(entry.dmrs, "symbol_indices")
        error("sixgr:conformance:MissingPUSCHDMRSSymbolContract", ...
            "FRC %s does not encode its PUSCH DM-RS symbol indices.", ...
            string(entry.frc_id));
    end
    dmrsSubscripts = nrPUSCHDMRSIndices(tx.Carrier, tx.PUSCH, ...
        "IndexStyle", "subscript", "IndexBase", "0based");
    actualDMRSSymbols = unique(double(dmrsSubscripts(:, 2)).', "stable");
    expectedDMRSSymbols = double(entry.dmrs.symbol_indices(:).');
    if ~isequal(actualDMRSSymbols, expectedDMRSSymbols)
        error("sixgr:conformance:PUSCHDMRSSymbolMismatch", ...
            ("FRC %s encodes PUSCH DM-RS symbol(s) %s, but the truth Tx " + ...
            "materialized %s."), string(entry.frc_id), ...
            mat2str(expectedDMRSSymbols), mat2str(actualDMRSSymbols));
    end
    configuredDifference_dB = ...
        double(entry.dmrs.data_to_dmrs_epre_db);
    if abs(configuredDifference_dB + 3) <= 1e-12
        % TS 38.104's normative -3 dB token is beta=sqrt(2), i.e. an
        % exact linear DM-RS/data power ratio of two.
        expectedDMRSPowerScale = 2;
    else
        expectedDMRSPowerScale = 10.^(-configuredDifference_dB / 10);
    end
    actualDMRSPowerScale = double(sixgr.util.structGet( ...
        tx, "DMRSPowerScale", NaN));
    if ~(isscalar(actualDMRSPowerScale) && ...
            isfinite(actualDMRSPowerScale) && ...
            actualDMRSPowerScale > 0 && ...
            abs(actualDMRSPowerScale - expectedDMRSPowerScale) <= ...
            64 * eps(max(expectedDMRSPowerScale, 1)))
        error("sixgr:conformance:PUSCHDMRSPowerScaleMismatch", ...
            ("FRC %s requires realized DM-RS/data power scale %.15g, " + ...
            "but the truth Tx disclosed %s. TS 38.104 slot-energy SNR " ...
            + "conversion cannot proceed."), string(entry.frc_id), ...
            expectedDMRSPowerScale, mat2str(actualDMRSPowerScale));
    end
end

expectedG = double(entry.coding.g_bits_per_slot);
if string(entry.direction) == "downlink" && ...
        any(mod(double(localCarrierAbsoluteSlot(tx.Carrier)), 20) == ...
        double(entry.coding.tracking_slot_indices))
    expectedG = double(entry.coding.g_bits_tracking_slots);
end
actualG = double(tx.G);
if ~(isscalar(actualG) && actualG == expectedG)
    error("sixgr:conformance:RateMatchedBitCountMismatch", ...
        "FRC %s requires G=%d bits in this slot, but the truth Tx produced %s.", ...
        string(entry.frc_id), expectedG, mat2str(actualG));
end
if string(tx.TargetCodeRate) == ""
    error("sixgr:conformance:MissingTargetCodeRate", ...
        "Truth Tx did not disclose its target code rate.");
end
expectedRate = double(entry.coding.target_code_rate_numerator) / ...
    double(entry.coding.target_code_rate_denominator);
if abs(double(tx.TargetCodeRate) - expectedRate) > 10 * eps(expectedRate)
    error("sixgr:conformance:TargetCodeRateMismatch", ...
        "FRC %s requires target code rate %.15g, truth Tx used %.15g.", ...
        string(entry.frc_id), expectedRate, double(tx.TargetCodeRate));
end
end

function localAssertTruthReceiver(entry, tx, rx)
requiredLogical = ["ReceiverUsable", "DecodeUsable", "StrictReceiverEvidenceOk"];
for field = requiredLogical
    if ~isfield(rx, char(field)) || ~logical(rx.(field))
        reason = string(sixgr.util.structGet(rx, "FailureReason", ...
            "required truth receiver evidence unavailable"));
        error("sixgr:conformance:TruthReceiverUnavailable", ...
            "FRC %s truth receiver is unavailable (%s=false): %s", ...
            string(entry.frc_id), field, reason);
    end
end
if ~isfield(rx, "TransportBlock") || ...
        numel(rx.TransportBlock) ~= double(entry.coding.tbs_bits)
    error("sixgr:conformance:DecodedTransportBlockUnavailable", ...
        "FRC %s truth receiver did not return an exact-length decoded transport block.", ...
        string(entry.frc_id));
end
truthStatus = lower(string(sixgr.util.structGet(rx, "TruthStatus", "")));
for forbidden = ["proxy", "fallback", "synthetic", "unavailable"]
    if contains(truthStatus, forbidden)
        error("sixgr:conformance:NonTruthReceiverStatus", ...
            "FRC %s receiver truth status '%s' contains forbidden token '%s'.", ...
            string(entry.frc_id), truthStatus, forbidden);
    end
end
if logical(rx.Ok) && ...
        ~isequal(int8(rx.TransportBlock(:)), int8(tx.TransportBlock(:)))
    error("sixgr:conformance:CRCBitIntegrityMismatch", ...
        "FRC %s reported CRC pass but did not recover the transmitted TB exactly.", ...
        string(entry.frc_id));
end
end

function [metric, denominator, eventCount] = localMetricCounts( ...
        metricName, numTB, numDelivered, numFailedTB, numTransmissions)
switch string(metricName)
    case "block_error_rate"
        denominator = double(numTB);
        eventCount = double(numFailedTB);
    case "fraction_of_maximum_throughput"
        denominator = double(numTransmissions);
        eventCount = double(numDelivered);
    otherwise
        error("sixgr:conformance:UnsupportedRequirementMetric", ...
            "Unsupported FRC requirement metric '%s'.", string(metricName));
end
if denominator <= 0
    error("sixgr:conformance:EmptyFRCMeasurement", ...
        "FRC measurement produced no statistical observations.");
end
metric = eventCount / denominator;
end

function [lower, upper, oneLower, oneUpper, method] = ...
        localMetricConfidenceBounds(metricName, eventCount, denominator, ...
        deliveredByTB, attemptsByTB, confidence, configuredMaxAttempts)
[lower, upper, oneLower, oneUpper, method] = ...
    sixgr.conformance.metricConfidenceBounds( ...
    metricName, eventCount, denominator, deliveredByTB, attemptsByTB, ...
    confidence, configuredMaxAttempts);
end

function tf = localConfidenceSeparated(lower, upper, requirement)
target = double(requirement.target_fraction);
tf = upper < target || lower > target;
end

function tf = localComparatorPass(value, requirement)
switch string(requirement.comparator)
    case "less_than_or_equal"
        tf = isfinite(value) && value <= double(requirement.target_fraction);
    case "greater_than_or_equal"
        tf = isfinite(value) && value >= double(requirement.target_fraction);
    otherwise
        error("sixgr:conformance:UnsupportedRequirementComparator", ...
            "Unsupported comparator '%s'.", string(requirement.comparator));
end
tf = logical(tf);
end

function tf = localConfidenceSupportsPass(oneSidedLower, oneSidedUpper, requirement)
switch string(requirement.comparator)
    case "less_than_or_equal"
        tf = isfinite(oneSidedUpper) && ...
            oneSidedUpper <= double(requirement.target_fraction);
    case "greater_than_or_equal"
        tf = isfinite(oneSidedLower) && ...
            oneSidedLower >= double(requirement.target_fraction);
    otherwise
        tf = false;
end
tf = logical(tf);
end

function tf = localReferencePointStatisticallyQualified(row, requirement, opt)
% A reference-point decision is statistically eligible only after the
% predeclared fixed sample has actually completed.  A tiny caller override
% must never inherit the "full" label and qualify by accident.
if ~logical(opt.ConfidenceQualificationEligible) || ...
        double(row.TransportBlocks) < ...
        double(opt.RequiredQualificationTransportBlocks)
    tf = false;
    return;
end
if string(requirement.metric) == "block_error_rate" && ...
        double(requirement.target_fraction) <= 1e-4
    % The rare-error sample floor is sized for the one-sided zero-error
    % upper confidence bound.  The pass/fail outcome itself is evaluated
    % separately by localConfidenceSupportsPass.
    tf = true;
else
    tf = logical(row.PrecisionTargetMet);
end
end

