function result = runFRCPoint(frcId, conditionId, varargin)
%RUNFRCPOINT Run a standards-anchored NR fixed-reference-channel point.
%
%   RESULT = sixgr.conformance.runFRCPoint(FRCID, CONDITIONID) resolves one
%   catalog record, drives the existing truth PDSCH or PUSCH chain over an
%   SNR sweep, and reports both:
%
%     * the normative, one-sided performance at the required SNR; and
%     * a nonnormative symmetric SNR-at-target regression diagnostic.
%
%   FRCID may be either catalog.entries(i).id or the standards FRC name.
%   CONDITIONID is required when the standards FRC name is not unique.
%
%   Important: the symmetric measured-minus-required SNR check is not a
%   3GPP conformance rule. 3GPP specifies minimum performance at a stated
%   SNR. The symmetric check is retained only as a simulator-regression
%   diagnostic and is labelled as such in RESULT.
%
%   Selected name-value options:
%     CatalogPath                  alternate strict catalog
%     SNRGrid_dB                   explicit sweep (required SNR is added)
%     ExecutionProfile            "full" (default) or "smoke"
%     MinTransportBlocks          lower sequential-sampling bound
%     MaxTransportBlocks          upper sequential-sampling bound
%     BatchSize                   TBs between confidence checks
%     ConfidenceLevel             confidence level (default 0.95)
%     MaxConfidenceHalfWidth      desired two-sided metric-interval
%                                  half-width (reported for full runs but
%                                  not used as SNR-bracket precision)
%     Seed                         deterministic experiment seed
%     Tolerance_dB                 project diagnostic tolerance
%     RequireExactStandardExecution
%                                  fail before simulation unless the full
%                                  standardized test waveform and timeline
%                                  can be materialized (default false)
%     RequireExactDataChannelExecution
%                                  fail unless the selected PDSCH/PUSCH
%                                  allocation, coding, DM-RS, precoding,
%                                  channel, and SNR contracts are exact
%     ValidateSetupOnly            build Tx once and validate exact TBS/G
%                                  without running channel Monte Carlo
%     AssertPass                   fail after the sweep when the project
%                                  diagnostic does not pass
%     PrintTable                   print the required six-column report
%
%   No proxy, lookup-table, synthetic-row, or unavailable-receiver rescue
%   path is used. Any unavailable truth trial fails loudly.

if nargin < 1
    frcId = "";
end
if nargin < 2
    conditionId = "";
end

ip = inputParser;
ip.FunctionName = "sixgr.conformance.runFRCPoint";
ip.addRequired("frcId", @localTextScalar);
ip.addRequired("conditionId", @localTextScalar);
ip.addParameter("CatalogPath", "", @localTextScalar);
ip.addParameter("SNRGrid_dB", [], @localFiniteVector);
ip.addParameter("ExecutionProfile", "full", ...
    @(v) localMemberText(v, ["full", "smoke"]));
ip.addParameter("MinTransportBlocks", [], @localOptionalPositiveInteger);
ip.addParameter("MaxTransportBlocks", [], @localOptionalPositiveInteger);
ip.addParameter("BatchSize", [], @localOptionalPositiveInteger);
ip.addParameter("ConfidenceLevel", 0.95, ...
    @(v) isnumeric(v) && isreal(v) && isscalar(v) && isfinite(v) && v > 0 && v < 1);
ip.addParameter("MaxConfidenceHalfWidth", [], ...
    @(v) isempty(v) || (isnumeric(v) && isreal(v) && isscalar(v) && ...
    isfinite(v) && v > 0 && v < 1));
ip.addParameter("MinimumBlockErrors", 25, @localNonnegativeInteger);
ip.addParameter("StopWhenConfidenceSeparated", true, @localLogicalScalar);
ip.addParameter("Seed", 38104, @localSeed);
ip.addParameter("Tolerance_dB", [], ...
    @(v) isempty(v) || (isnumeric(v) && isreal(v) && isscalar(v) && ...
    isfinite(v) && v > 0));
ip.addParameter("MaxDecoderIterations", [], @localOptionalPositiveInteger);
ip.addParameter("EvaluateSymmetricRegression", true, @localLogicalScalar);
ip.addParameter("ParallelWorkers", 0, @localNonnegativeInteger);
ip.addParameter("RequireExactStandardExecution", false, @localLogicalScalar);
ip.addParameter("RequireExactDataChannelExecution", true, @localLogicalScalar);
ip.addParameter("ValidateSetupOnly", false, @localLogicalScalar);
ip.addParameter("AssertPass", false, @localLogicalScalar);
ip.addParameter("PrintTable", true, @localLogicalScalar);
ip.addParameter("Verbose", true, @localLogicalScalar);
ip.parse(frcId, conditionId, varargin{:});
opt = ip.Results;

catalog = sixgr.conformance.frcCatalog(opt.CatalogPath);
entry = localResolveEntry(catalog.entries, string(frcId), string(conditionId));
opt = localFinalizeOptions(opt, entry, catalog.project_diagnostic_policy);

localRequireTruthDependencies(entry);
[standardExecutionExact, standardExecutionBlockers, ...
    dataChannelExecutionExact, dataChannelExecutionBlockers, ...
    dataChannelExecutionContract] = ...
    localAssessStandardExecution(entry);
if logical(opt.RequireExactStandardExecution) && ~standardExecutionExact
    error("sixgr:conformance:IncompleteStandardExecution", ...
        ("FRC '%s' condition '%s' cannot be labelled as an exact standards " + ...
        "execution by the current truth chain. Blocker(s): %s"), ...
        string(entry.frc_id), string(entry.condition.id), ...
        strjoin(standardExecutionBlockers, "; "));
end
if logical(opt.RequireExactDataChannelExecution) && ~dataChannelExecutionExact
    error("sixgr:conformance:IncompleteDataChannelExecution", ...
        ("FRC '%s' condition '%s' cannot be used for the data-channel " + ...
        "reference-point gate. Blocker(s): %s"), ...
        string(entry.frc_id), string(entry.condition.id), ...
        strjoin(dataChannelExecutionBlockers, "; "));
end
if ~standardExecutionExact && logical(opt.Verbose)
    warning("sixgr:conformance:ProjectDiagnosticOnly", ...
        ("Running '%s' as a truth-chain project diagnostic, not as a complete " + ...
        "standards execution. Blocker(s): %s"), ...
        string(entry.id), strjoin(standardExecutionBlockers, "; "));
end

[carrier, channelCfg, waveformCfg, precoder] = localBuildExecution(entry, opt);
if logical(opt.ValidateSetupOnly)
    result = localRunSetupValidation(entry, carrier, channelCfg, ...
        waveformCfg, precoder, standardExecutionExact, ...
        standardExecutionBlockers, dataChannelExecutionExact, ...
        dataChannelExecutionBlockers, dataChannelExecutionContract, opt);
    return;
end
requiredSNR_dB = double(entry.requirement.required_snr_db);
[snrGrid, snrSeedIndices] = localResolveSNRGrid( ...
    opt.SNRGrid_dB, requiredSNR_dB, double(opt.Tolerance_dB), ...
    string(opt.ExecutionProfile), logical(opt.EvaluateSymmetricRegression));

priorRng = rng;
rngCleanup = onCleanup(@() rng(priorRng)); %#ok<NASGU>
rng(double(opt.Seed), "twister");

pointRows = repmat(localEmptyPointRow(), numel(snrGrid), 1);
pointDetails = cell(numel(snrGrid), 1);
for snrIndex = 1:numel(snrGrid)
    snr_dB = double(snrGrid(snrIndex));
    if logical(opt.Verbose)
        fprintf("FRC %s | %s | SNR %.3f dB\n", ...
            string(entry.frc_id), string(entry.condition.id), snr_dB);
    end
    [pointRows(snrIndex), pointDetails{snrIndex}] = localRunSNR( ...
        entry, carrier, channelCfg, waveformCfg, precoder, snr_dB, ...
        double(snrSeedIndices(snrIndex)), opt);
end

sweep = struct2table(pointRows);
if logical(opt.EvaluateSymmetricRegression)
    [measuredSNR_dB, crossingInfo] = localFindTargetCrossing( ...
        sweep.SNR_dB, sweep.MetricEstimate, sweep.ConfidenceLower, ...
        sweep.ConfidenceUpper, sweep.ConfidenceDenominator, ...
        sweep.ConfidenceMethod, ...
        logical(opt.ConfidenceQualificationEligible), entry.requirement, ...
        requiredSNR_dB, double(opt.Tolerance_dB), ...
        double(opt.ConfidenceLevel));
else
    measuredSNR_dB = NaN;
    crossingInfo = localUnevaluatedSymmetricCrossing( ...
        entry.requirement, requiredSNR_dB, double(opt.Tolerance_dB), ...
        double(opt.ConfidenceLevel));
end
delta_dB = measuredSNR_dB - requiredSNR_dB;
tolerance_dB = double(opt.Tolerance_dB);

requiredIndex = find(abs(double(sweep.SNR_dB) - requiredSNR_dB) <= 1e-10, 1);
if isempty(requiredIndex)
    error("sixgr:conformance:RequiredSNRMissing", ...
        "Internal error: the required SNR %.12g dB is absent from the sweep.", ...
        requiredSNR_dB);
end
normativePointEstimatePass = localComparatorPass( ...
    double(sweep.MetricEstimate(requiredIndex)), entry.requirement);
normativeConfidenceSupportsPass = ...
    logical(opt.ConfidenceQualificationEligible) && ...
    localConfidenceSupportsPass( ...
    double(sweep.OneSidedLower(requiredIndex)), ...
    double(sweep.OneSidedUpper(requiredIndex)), entry.requirement);
referencePointStatisticallyQualified = ...
    localReferencePointStatisticallyQualified( ...
    sweep(requiredIndex,:), entry.requirement, opt);
normativePass = standardExecutionExact && normativePointEstimatePass;

projectCrossingPass = dataChannelExecutionExact && ...
    logical(crossingInfo.StatisticallyQualified) && isfinite(delta_dB) && ...
    logical(crossingInfo.BracketWithinTolerance) && ...
    abs(delta_dB) <= tolerance_dB;
report = table( ...
    string(entry.frc_id), string(entry.condition.id), requiredSNR_dB, ...
    measuredSNR_dB, delta_dB, logical(projectCrossingPass), ...
    'VariableNames', { ...
    'FRC', 'condition', 'required_SNR_dB', 'measured_SNR_dB', ...
    'delta_dB', 'pass'});

if logical(opt.PrintTable)
    disp(report);
end

result = struct();
result.ContractVersion = "sixgr_conformance_frc_point/v1";
result.EntryId = string(entry.id);
result.FRC = string(entry.frc_id);
result.Condition = string(entry.condition.id);
result.Direction = string(entry.direction);
result.PhysicalChannel = string(entry.physical_channel);
result.ExecutionBackend = "existing_truth_" + lower(string(entry.physical_channel)) + "_tx_rx";
result.ApproximationMode = "none";
result.Source = "existing_truth_phy_execution";
result.StandardExecution = struct( ...
    "Exact", logical(standardExecutionExact), ...
    "Status", localExactStatus(standardExecutionExact), ...
    "Blockers", standardExecutionBlockers, ...
    "NormativeResultEligible", logical(standardExecutionExact), ...
    "NoProxyOrFallbackUsed", true);
result.DataChannelExecution = struct( ...
    "Exact", logical(dataChannelExecutionExact), ...
    "Status", localDataChannelStatus(dataChannelExecutionExact), ...
    "Blockers", dataChannelExecutionBlockers, ...
    "Contract", dataChannelExecutionContract, ...
    "ReferencePointResultEligible", logical(dataChannelExecutionExact), ...
    "NoProxyOrFallbackUsed", true);
result.Requirement = entry.requirement;
result.SNRDefinition = string(entry.condition.snr_definition);
result.Sweep = sweep;
result.PointDetails = pointDetails;
result.RequiredPoint = sweep(requiredIndex, :);
result.RequiredSNR_dB = requiredSNR_dB;
result.MeasuredSNRAtTarget_dB = measuredSNR_dB;
result.Delta_dB = delta_dB;
result.Tolerance_dB = tolerance_dB;
result.NormativePass = logical(normativePass);
result.NormativePointEstimatePass = logical(normativePointEstimatePass);
result.NormativeConfidenceSupportsPass = logical( ...
    standardExecutionExact && normativeConfidenceSupportsPass);
result.NormativeSemantics = "one_sided_minimum_performance_at_required_snr";
result.ReferencePointPass = logical(dataChannelExecutionExact && ...
    referencePointStatisticallyQualified && normativePointEstimatePass && ...
    normativeConfidenceSupportsPass);
result.ReferencePointPointEstimatePass = logical( ...
    dataChannelExecutionExact && normativePointEstimatePass);
result.ReferencePointConfidenceSupportsPass = logical( ...
    dataChannelExecutionExact && normativeConfidenceSupportsPass);
result.ReferencePointStatisticallyQualified = logical( ...
    dataChannelExecutionExact && referencePointStatisticallyQualified);
result.ReferencePointNormative = false;
result.ReferencePointSemantics = ...
    "one_sided_required_snr_data_channel_regression_in_incomplete_test_waveform";
result.ProjectDiagnosticPass = logical(projectCrossingPass);
result.ProjectDiagnosticEvaluated = logical(opt.EvaluateSymmetricRegression);
result.ProjectDiagnosticStatisticallyQualified = logical( ...
    opt.EvaluateSymmetricRegression && crossingInfo.StatisticallyQualified);
result.ProjectDiagnosticNormative = false;
result.ProjectDiagnosticSemantics = ...
    "symmetric_snr_at_target_crossing_nonnormative_regression_check";
result.ConfidenceQualification = struct( ...
    "Eligible", logical(opt.ConfidenceQualificationEligible), ...
    "SamplingPlan", string(opt.ConfidenceSamplingPlan), ...
    "MaxConfidenceHalfWidth", double(opt.MaxConfidenceHalfWidth), ...
    "RequiredPointHalfWidth", ...
        double(sweep.ConfidenceHalfWidth(requiredIndex)), ...
    "RequiredPointPrecisionTargetMet", ...
        logical(sweep.PrecisionTargetMet(requiredIndex)), ...
    "RequiredPointHalfWidthUsedForQualification", false, ...
    "ReferencePointQualification", ...
        "one_sided_confidence_bound_at_required_snr", ...
    "ProjectDiagnosticQualification", ...
        "simultaneous_directional_bounds_at_prespecified_snr_tolerance_endpoints", ...
    "ProjectBracketWidth_dB", double(crossingInfo.BracketWidth_dB), ...
    "ProjectMaximumBracketWidth_dB", ...
        double(crossingInfo.MaximumBracketWidth_dB), ...
    "StatisticalUnit", "independently_sampled_transport_block", ...
    "HARQRetransmissionsAreIndependentTrials", false, ...
    "FadingChannelReseededPerTransportBlock", ...
        string(entry.condition.kind) == "fading");
result.Crossing = crossingInfo;
% Backward-compatible field: statistical qualification now names the
% one-sided required-SNR decision used by the reference-point gate.  The
% nonnormative symmetric crossing has its own explicit field above.
result.StatisticallyQualified = logical( ...
    dataChannelExecutionExact && referencePointStatisticallyQualified);
result.Report = report;
result.Table = report;
result.Options = localPublicOptions(opt);

if logical(opt.AssertPass) && ~logical(projectCrossingPass)
    error("sixgr:conformance:FRCPointOutsideTolerance", ...
        ("FRC %s | %s failed the nonnormative symmetric project diagnostic: " + ...
        "required %.3f dB, measured %.3f dB, delta %.3f dB, tolerance +/-%.3f dB. " ...
        + "Crossing status: %s."), ...
        string(entry.frc_id), string(entry.condition.id), requiredSNR_dB, ...
        measuredSNR_dB, delta_dB, tolerance_dB, string(crossingInfo.Status));
end
end

function result = localRunSetupValidation(entry, carrierTemplate, execution, ...
        cfg, precoder, standardExecutionExact, standardExecutionBlockers, ...
        dataChannelExecutionExact, dataChannelExecutionBlockers, ...
        dataChannelExecutionContract, opt)
targetCodeRate = double(execution.TargetCodeRate);
tbBits = zeros(double(entry.coding.tbs_bits), 1, "int8");
rv = double(entry.harq.rv_sequence(1));
setupSlots = localSetupValidationSlots(entry);
setupRows = repmat(localEmptySetupRow(), numel(setupSlots), 1);
setupTxEvidence = cell(numel(setupSlots), 1);
for setupIndex = 1:numel(setupSlots)
    carrier = localCloneCarrier(carrierTemplate);
    absoluteSlot = double(setupSlots(setupIndex));
    carrier = localSetCarrierAbsoluteSlot(carrier, absoluteSlot);
    trackingSlot = localIsDLTrackingSlot(entry, absoluteSlot);
    if string(entry.direction) == "downlink"
        setupPDSCH = localConfigurePDSCHForSlot( ...
            entry, carrier, execution.PhysicalChannel);
        setupPrecoder = localPDSCHPrecoderForSlot( ...
            entry, carrier, cfg, double(opt.Seed) + absoluteSlot + 1);
        [tx, txInfo] = sixgr.phy.dl.PDSCH_Tx(cfg, ...
            "Carrier", carrier, ...
            "PDSCH", setupPDSCH, ...
            "TransportBlockBits", tbBits, ...
            "TransportBlockSizeOverride", double(entry.coding.tbs_bits), ...
            "RV", rv, ...
            "TargetCodeRate", targetCodeRate, ...
            "XOverhead", 0, ...
            "NumTxAnt", double(entry.mimo.tx_antennas), ...
            "PrecodingMatrix", setupPrecoder, ...
            "ExecutionProfile", "phy_calibration", ...
            "CompactOutput", ~trackingSlot);
        if trackingSlot
            tx = localMaterializeTrackingCSIRS(entry, carrier, tx);
        end
    else
        [tx, txInfo] = sixgr.phy.ul.PUSCH_Tx(cfg, ...
            "Carrier", carrier, ...
            "PUSCH", execution.PhysicalChannel, ...
            "TransportBlockBits", tbBits, ...
            "TransportBlockSizeOverride", double(entry.coding.tbs_bits), ...
            "RV", rv, ...
            "TargetCodeRate", targetCodeRate, ...
            "XOverhead", 0, ...
            "NumTxAnt", double(entry.mimo.tx_antennas), ...
            "CompactOutput", true);
    end
    localAssertExactTx(entry, tx, setupIndex);
    expectedG = double(entry.coding.g_bits_per_slot);
    if trackingSlot
        expectedG = double(entry.coding.g_bits_tracking_slots);
    end
    trackingMaterialized = trackingSlot && ...
        logical(sixgr.util.structGet(tx, "TrackingCSIRS.Materialized", false));
    setupRows(setupIndex) = struct( ...
        "FRC", string(entry.frc_id), ...
        "condition", string(entry.condition.id), ...
        "slot", absoluteSlot, ...
        "slot_type", localSetupSlotType(trackingSlot), ...
        "modulation", string(entry.coding.modulation), ...
        "layers", double(entry.mimo.layers), ...
        "required_TBS_bits", double(entry.coding.tbs_bits), ...
        "actual_TBS_bits", double(tx.TransportBlockSize), ...
        "required_G_bits", expectedG, ...
        "actual_G_bits", double(tx.G), ...
        "tracking_csirs_materialized", logical(trackingMaterialized), ...
        "pass", true);
    setupTxEvidence{setupIndex} = localCompactTxEvidence(tx, txInfo);
end
setupTable = struct2table(setupRows);
if logical(opt.PrintTable)
    disp(setupTable);
end

requiredSNR = double(entry.requirement.required_snr_db);
report = table(string(entry.frc_id), string(entry.condition.id), ...
    requiredSNR, NaN, NaN, false, ...
    'VariableNames', {'FRC', 'condition', 'required_SNR_dB', ...
    'measured_SNR_dB', 'delta_dB', 'pass'});
result = struct( ...
    "ContractVersion", "sixgr_conformance_frc_point/v1", ...
    "EntryId", string(entry.id), ...
    "FRC", string(entry.frc_id), ...
    "Condition", string(entry.condition.id), ...
    "Direction", string(entry.direction), ...
    "PhysicalChannel", string(entry.physical_channel), ...
    "ExecutionBackend", ...
        "existing_truth_" + lower(string(entry.physical_channel)) + "_tx_setup", ...
    "ApproximationMode", "none", ...
    "Source", "existing_truth_phy_execution", ...
    "StandardExecution", struct( ...
        "Exact", logical(standardExecutionExact), ...
        "Status", localExactStatus(standardExecutionExact), ...
        "Blockers", {standardExecutionBlockers}, ...
        "NormativeResultEligible", false, ...
        "NoProxyOrFallbackUsed", true), ...
    "DataChannelExecution", struct( ...
        "Exact", logical(dataChannelExecutionExact), ...
        "Status", localDataChannelStatus(dataChannelExecutionExact), ...
        "Blockers", {dataChannelExecutionBlockers}, ...
        "Contract", dataChannelExecutionContract, ...
        "ReferencePointResultEligible", false, ...
        "NoProxyOrFallbackUsed", true), ...
    "SetupValidationOnly", true, ...
    "SetupValidation", struct( ...
        "Pass", all(setupTable.pass), ...
        "Table", setupTable, ...
        "TxEvidence", {setupTxEvidence}), ...
    "Requirement", entry.requirement, ...
    "SNRDefinition", string(entry.condition.snr_definition), ...
    "Sweep", table(), ...
    "PointDetails", {{}}, ...
    "RequiredSNR_dB", requiredSNR, ...
    "MeasuredSNRAtTarget_dB", NaN, ...
    "Delta_dB", NaN, ...
    "Tolerance_dB", double(opt.Tolerance_dB), ...
    "NormativePass", false, ...
    "NormativePointEstimatePass", false, ...
    "NormativeConfidenceSupportsPass", false, ...
    "NormativeSemantics", "not_evaluated_setup_validation_only", ...
    "ReferencePointPass", false, ...
    "ReferencePointPointEstimatePass", false, ...
    "ReferencePointConfidenceSupportsPass", false, ...
    "ReferencePointStatisticallyQualified", false, ...
    "ReferencePointNormative", false, ...
    "ReferencePointSemantics", "not_evaluated_setup_validation_only", ...
    "ProjectDiagnosticPass", false, ...
    "ProjectDiagnosticEvaluated", false, ...
    "ProjectDiagnosticStatisticallyQualified", false, ...
    "ProjectDiagnosticNormative", false, ...
    "ProjectDiagnosticSemantics", "not_evaluated_setup_validation_only", ...
    "StatisticallyQualified", false, ...
    "Report", report, ...
    "Table", report, ...
    "Options", localPublicOptions(opt));
end

function [row, detail] = localRunSNR(entry, carrierTemplate, channelCfg, ...
        waveformCfg, precoder, snr_dB, snrIndex, opt)
carrier = localCloneCarrier(carrierTemplate);
parallelWorkers = double(opt.ParallelWorkers);
if parallelWorkers > 1 && ...
        ~license('test','Distrib_Computing_Toolbox')
    error("sixgr:conformance:ParallelQualificationUnavailable", ...
        ["ParallelWorkers=%d was requested, but Parallel Computing " ...
        "Toolbox is unavailable. No serial fallback is permitted."], ...
        parallelWorkers);
end
parallelPoolWorkers = 0;
parallelPoolType = "none";
if parallelWorkers > 1
    pool = gcp('nocreate');
    if isempty(pool)
        pool = parpool('Processes',parallelWorkers);
    elseif isa(pool, 'parallel.ThreadPool')
        error("sixgr:conformance:ProcessPoolRequired", ...
            "The exact NR waveform functions used by FRC qualification " + ...
            "do not support thread-based workers. Delete the thread pool " + ...
            "and use a process-based pool.");
    elseif double(pool.NumWorkers) < parallelWorkers
        error("sixgr:conformance:ParallelPoolTooSmall", ...
            ["The active pool has %d worker(s), but the YAML/requested " ...
            "qualification policy requires %d."], ...
            double(pool.NumWorkers),parallelWorkers);
    end
    parallelPoolWorkers = min(parallelWorkers,double(pool.NumWorkers));
    parallelPoolType = string(class(pool));
end

bitStream = RandStream("mt19937ar", ...
    "Seed", localFoldSeed(double(opt.Seed) + 104729 * snrIndex));
numTB = 0;
numDelivered = 0;
numTransmissions = 0;
numFailedTB = 0;
tbDelivered = false(double(opt.MaxTransportBlocks), 1);
tbAttempts = zeros(double(opt.MaxTransportBlocks), 1);
tbFirstTransmissionIndex = zeros(double(opt.MaxTransportBlocks), 1);
tbFadingChannelSeed = nan(double(opt.MaxTransportBlocks), 1);
maxHARQAttempts = double(entry.harq.max_transmissions);
tbNoiseSeedByAttempt = zeros(double(opt.MaxTransportBlocks), ...
    maxHARQAttempts, "uint32");
tbRVByAttempt = repmat(uint8(255), double(opt.MaxTransportBlocks), ...
    maxHARQAttempts);
tbAbsoluteSlotByAttempt = repmat(uint64(intmax("uint64")), ...
    double(opt.MaxTransportBlocks), maxHARQAttempts);
tbChannelStartSampleByAttempt = repmat(uint64(intmax("uint64")), ...
    double(opt.MaxTransportBlocks), maxHARQAttempts);
tbHARQProcessID = repmat(uint16(intmax("uint16")), ...
    double(opt.MaxTransportBlocks), 1);
stopReason = "max_transport_blocks";
noiseProvenance = struct();
lastRxEvidence = struct();
firstTxEvidence = struct();
lastAttemptTxEvidence = cell(0, 1);
lastAttemptRxEvidence = cell(0, 1);
lastPropagationEvidence = struct();

while numTB < double(opt.MaxTransportBlocks)
    remaining = double(opt.MaxTransportBlocks) - numTB;
    batchCount = min(double(opt.BatchSize), remaining);
    payloadBits = cell(batchCount,1);
    for batchIndex = 1:batchCount
        payloadBits{batchIndex} = int8(randi(bitStream, [0 1], ...
            double(entry.coding.tbs_bits), 1));
    end
    batchResults = cell(batchCount,1);
    if parallelWorkers > 1
        parfor (batchIndex = 1:batchCount, parallelWorkers)
            transportBlockIndex = numTB + batchIndex;
            [delivered, attempts, evidence] = ...
                localRunIndependentTransportBlock( ...
                entry,carrier,channelCfg,waveformCfg,precoder, ...
                payloadBits{batchIndex},snr_dB,snrIndex, ...
                transportBlockIndex,opt);
            batchResults{batchIndex} = struct( ...
                "Delivered",logical(delivered), ...
                "Attempts",double(attempts),"Evidence",evidence);
        end
    else
        for batchIndex = 1:batchCount
            transportBlockIndex = numTB + batchIndex;
            [delivered, attempts, evidence] = ...
                localRunIndependentTransportBlock( ...
                entry,carrier,channelCfg,waveformCfg,precoder, ...
                payloadBits{batchIndex},snr_dB,snrIndex, ...
                transportBlockIndex,opt);
            batchResults{batchIndex} = struct( ...
                "Delivered",logical(delivered), ...
                "Attempts",double(attempts),"Evidence",evidence);
        end
    end
    for batchIndex = 1:batchCount
        batchResult = batchResults{batchIndex};
        delivered = logical(batchResult.Delivered);
        attempts = double(batchResult.Attempts);
        evidence = batchResult.Evidence;
        firstTransmissionIndex = numTransmissions + 1;
        numTB = numTB + 1;
        tbDelivered(numTB) = logical(delivered);
        tbAttempts(numTB) = double(attempts);
        tbFirstTransmissionIndex(numTB) = double(firstTransmissionIndex);
        tbFadingChannelSeed(numTB) = double(evidence.Seeds.FadingChannelSeed);
        attemptNoiseSeeds = uint32(evidence.Seeds.NoiseSeedByAttempt(:).');
        attemptRVs = uint8(evidence.Seeds.RVByAttempt(:).');
        tbNoiseSeedByAttempt(numTB, 1:numel(attemptNoiseSeeds)) = ...
            attemptNoiseSeeds;
        tbRVByAttempt(numTB, 1:numel(attemptRVs)) = attemptRVs;
        attemptSlots = uint64(evidence.Timing.AbsoluteSlotByAttempt(:).');
        attemptStartSamples = uint64( ...
            evidence.Timing.ChannelStartSampleByAttempt(:).');
        tbAbsoluteSlotByAttempt(numTB, 1:numel(attemptSlots)) = attemptSlots;
        tbChannelStartSampleByAttempt(numTB, 1:numel(attemptStartSamples)) = ...
            attemptStartSamples;
        tbHARQProcessID(numTB) = uint16(evidence.Timing.HARQProcessID);
        numDelivered = numDelivered + double(delivered);
        numFailedTB = numFailedTB + double(~delivered);
        numTransmissions = numTransmissions + double(attempts);
        noiseProvenance = evidence.Noise;
        lastRxEvidence = evidence.Rx;
        lastAttemptTxEvidence = evidence.AttemptTx;
        lastAttemptRxEvidence = evidence.AttemptRx;
        lastPropagationEvidence = evidence.Propagation;
        if isempty(fieldnames(firstTxEvidence))
            firstTxEvidence = evidence.Tx;
        end
    end

    [metricEstimate, denominator, eventCount] = localMetricCounts( ...
        entry.requirement.metric, numTB, numDelivered, ...
        numFailedTB, numTransmissions);
    [ciLower, ciUpper, oneLower, oneUpper, confidenceMethod] = ...
        localMetricConfidenceBounds(entry.requirement.metric, ...
            eventCount, denominator, tbDelivered(1:numTB), ...
            tbAttempts(1:numTB), double(opt.ConfidenceLevel), ...
            double(entry.harq.max_transmissions));
    halfWidth = (ciUpper - ciLower) / 2;

    if numTB >= double(opt.MinTransportBlocks) && ...
            logical(opt.ConfidenceEarlyStoppingEnabled)
        enoughErrors = numFailedTB >= double(opt.MinimumBlockErrors);
        if halfWidth <= double(opt.MaxConfidenceHalfWidth)
            stopReason = "confidence_half_width_met";
            break;
        end
        confidenceSeparated = localConfidenceSeparated( ...
            ciLower, ciUpper, entry.requirement) || ...
            localConfidenceSupportsPass(oneLower, oneUpper, entry.requirement);
        if logical(opt.StopWhenConfidenceSeparated) && confidenceSeparated && ...
                (enoughErrors || string(entry.requirement.metric) ~= "block_error_rate" || ...
                oneUpper <= double(entry.requirement.target_fraction))
            stopReason = "confidence_interval_separated_from_target";
            break;
        end
    end
end

