end

function count = localChannelPadSamples(infoStruct, sampleRate, delaySpread)
count = double(sixgr.util.structGet(infoStruct, "MaximumChannelDelay", NaN));
if ~(isfinite(count) && count >= 0)
    pathDelays = double(sixgr.util.structGet(infoStruct, "PathDelays", []));
    if isempty(pathDelays)
        pathDelay = 10 * double(delaySpread);
    else
        pathDelay = max(pathDelays);
    end
    count = ceil(pathDelay * double(sampleRate)) + 128;
end
count = max(128, ceil(count) + 16);
end

