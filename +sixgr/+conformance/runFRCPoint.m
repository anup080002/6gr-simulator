function evidence = localCompactTxPrecodingPowerEvidence(tx)
precode = sixgr.util.structGet(tx, "PrecodeInfo", struct());
pageTrace = double(sixgr.util.structGet(precode, ...
    "PRGPrecoderTraceWWH", sixgr.util.structGet(precode, ...
    "PrecoderTraceWWH", [])));
pageTrace = reshape(pageTrace, 1, []);
normalizeW = logical(sixgr.util.structGet(precode, "NormalizeW", false));
numLayers = double(sixgr.util.structGet(precode, "NumLayers", NaN));
numPorts = double(sixgr.util.structGet(precode, "NumPorts", NaN));

isPDSCH = isfield(tx, "PDSCH") && ~isempty(tx.PDSCH);
if isPDSCH && ~isempty(pageTrace)
    targetTrace = 1;
    traceError = max(abs(pageTrace - targetTrace), [], "all");
    allPagesAtTarget = all(isfinite(pageTrace), "all") && ...
        traceError <= 1e-12;
    conductedOffset_dB = 10 .* log10(pageTrace);
    policy = "TS38101_4_conducted_no_precoding_gain_unit_total_power";
else
    targetTrace = double(sixgr.util.structGet(precode, ...
        "PRGPrecoderTraceTarget", NaN));
    traceError = NaN;
    allPagesAtTarget = false;
    conductedOffset_dB = NaN(size(pageTrace));
    policy = "tx_chain_reported_no_frc_pdsch_target";
end

evidence = struct( ...
    "NormalizeW", normalizeW, ...
    "NumLayers", numLayers, ...
    "NumPorts", numPorts, ...
    "PageTraceWWH", pageTrace, ...
    "TargetTraceWWH", targetTrace, ...
    "PageTraceMaxError", double(traceError), ...
    "AllPagesAtTarget", logical(allPagesAtTarget), ...
    "ConductedSNROffset_dB", double(conductedOffset_dB), ...
    "Policy", policy, ...
    "Source", "PDSCH_Tx.PrecodeInfo");
end

