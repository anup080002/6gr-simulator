function seed = localFoldSeed(value)
seed = mod(floor(double(value)), 2^32 - 1);
if seed < 0
    seed = seed + 2^32 - 1;
end
end

function tf = localTextScalar(value)
tf = ischar(value) || (isstring(value) && isscalar(value));
end

function tf = localMemberText(value, choices)
tf = localTextScalar(value) && any(lower(string(value)) == choices);
end

function tf = localFiniteVector(value)
tf = isempty(value) || (isnumeric(value) && isreal(value) && ...
    isvector(value) && all(isfinite(value), "all"));
end

function tf = localOptionalPositiveInteger(value)
tf = isempty(value) || (isnumeric(value) && isreal(value) && ...
    isscalar(value) && isfinite(value) && value > 0 && value == fix(value));
end

function tf = localNonnegativeInteger(value)
tf = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && value >= 0 && value == fix(value);
end

function tf = localLogicalScalar(value)
tf = (islogical(value) || isnumeric(value)) && isscalar(value) && ...
    isfinite(double(value)) && any(double(value) == [0, 1]);
end

function tf = localSeed(value)
tf = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && value >= 0 && value <= 2^32 - 1 && value == fix(value);
end
