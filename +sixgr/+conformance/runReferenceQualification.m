function out = runReferenceQualification(runFolder, varargin)
%RUNREFERENCEQUALIFICATION Execute and persist independent FRC references.
%
% A diagnostic profile writes frc_reference_diagnostic.csv only.  The
% production qualification filename is reserved for statistically eligible
% full executions, preventing a bounded development run from satisfying the
% final production reducer.

arguments
    runFolder {mustBeTextScalar}
end
arguments (Repeating)
    varargin
end

ip = inputParser;
ip.FunctionName = "sixgr.conformance.runReferenceQualification";
ip.addParameter("Profile", "full", @(v) any(lower(string(v)) == ["full","diagnostic"]));
ip.addParameter("EntryIds", localMandatoryAWGNEntries(), @(v) isstring(v) || iscellstr(v));
ip.addParameter("EntrySampling", {}, @(v) isstruct(v) || iscell(v) || isempty(v));
ip.addParameter("Tolerance_dB", 1.0, @(v) isnumeric(v) && isscalar(v) && isfinite(v) && v > 0);
ip.addParameter("ConfidenceLevel", 0.95, ...
    @(v) isnumeric(v) && isscalar(v) && isfinite(v) && v > 0 && v < 1);
ip.addParameter("MaxConfidenceHalfWidth", [], ...
    @(v) isempty(v) || (isnumeric(v) && isscalar(v) && isfinite(v) && v > 0));
ip.addParameter("MinTransportBlocks", [], @(v) isempty(v) || (isnumeric(v) && isscalar(v) && v >= 1));
ip.addParameter("MaxTransportBlocks", [], @(v) isempty(v) || (isnumeric(v) && isscalar(v) && v >= 1));
ip.addParameter("BatchSize", [], @(v) isempty(v) || (isnumeric(v) && isscalar(v) && v >= 1));
ip.addParameter("MinimumBlockErrors", 25, @(v) isnumeric(v) && isscalar(v) && v >= 0);
ip.addParameter("RequireSymmetricRegression", false, ...
    @(v) islogical(v) || (isnumeric(v) && isscalar(v)));
ip.addParameter("ParallelWorkers", 0, ...
    @(v) isnumeric(v) && isscalar(v) && isfinite(v) && v >= 0 && v == fix(v));
ip.addParameter("Resume", true, ...
    @(v) islogical(v) || (isnumeric(v) && isscalar(v)));
ip.addParameter("Verbose", true, @(v) islogical(v) || (isnumeric(v) && isscalar(v)));
ip.parse(varargin{:});
opt = ip.Results;

runFolder = char(string(runFolder));
layout = sixgr.report.resultLayout(runFolder);
sixgr.util.ensureFolder(layout.ReportCSVDir);
catalog = sixgr.conformance.frcCatalog();
catalogDigest = sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(catalog), "UTF-8")));
sourceIdentity = localSourceIdentity();
if lower(string(opt.Profile)) == "full"
    if strlength(sourceIdentity.GitCommit) ~= 40 || sourceIdentity.GitWorktreeDirty
        error("sixgr:conformance:QualificationSourceNotClean", ...
            ["Full FRC qualification requires one committed, clean source " + ...
            "state. Commit='%s', dirty=%d."], sourceIdentity.GitCommit, ...
            sourceIdentity.GitWorktreeDirty);
    end
end
entries = string(opt.EntryIds(:));
if isempty(entries) || numel(unique(entries)) ~= numel(entries)
    error("sixgr:conformance:InvalidQualificationEntrySet", ...
        "EntryIds must contain at least one unique FRC catalog entry id.");
end

checkpointDir = fullfile(layout.ReportCSVDir, "frc_reference_checkpoints");
sixgr.util.ensureFolder(checkpointDir);
rows = repmat(localEmptyRow(), numel(entries), 1);
entryResults = cell(numel(entries), 1);
resumed = false(numel(entries), 1);
for index = 1:numel(entries)
    entryId = entries(index);
    entryPolicy = localEntryPolicy(opt, entryId, catalogDigest, sourceIdentity);
    identitySHA256 = sixgr.util.sha256Hex(uint8(unicode2native( ...
        jsonencode(entryPolicy), "UTF-8")));
    checkpointPath = fullfile(checkpointDir, sprintf("%03d_%s.mat", ...
        index, localSafeToken(entryId)));
    pointProgressDir = fullfile(layout.ReportCSVDir, ...
        "frc_reference_progress", sprintf("%03d_%s", ...
        index, localSafeToken(entryId)));
    if logical(opt.Resume) && isfile(checkpointPath)
        checkpoint = load(checkpointPath);
        localValidateCheckpoint(checkpoint, checkpointPath, entryId, ...
            identitySHA256);
        rows(index) = checkpoint.Row;
        entryResults{index} = checkpoint.ExecutionResult;
        resumed(index) = true;
        localWritePartial(layout.ReportCSVDir, rows, index);
        if logical(opt.Verbose)
            fprintf("FRC qualification resumed %s from %s\n", ...
                entryId, checkpointPath);
        end
        continue;
    end
    rows(index).EntryId = entryId;
    rows(index).Required = true;
    rows(index).Profile = lower(string(opt.Profile));
    rows(index).CatalogSHA256 = string(catalogDigest);
    rows(index).ExecutionAttempted = true;
    result = struct();
    try
        entry = localCatalogEntry(catalog.entries, entryId);
        rows(index).FRC = string(entry.frc_id);
        rows(index).Condition = string(entry.condition.id);
        nv = { ...
            "ExecutionProfile", localExecutionProfile(opt.Profile), ...
            "Tolerance_dB", double(opt.Tolerance_dB), ...
            "ConfidenceLevel", double(opt.ConfidenceLevel), ...
            "MinimumBlockErrors", double(opt.MinimumBlockErrors), ...
            "EvaluateSymmetricRegression", ...
                logical(opt.RequireSymmetricRegression), ...
            "ParallelWorkers", double(opt.ParallelWorkers), ...
            "ProgressDirectory", pointProgressDir, ...
            "ProgressIdentitySHA256", string(identitySHA256), ...
            "ResumeProgress", logical(opt.Resume), ...
            "RequireExactStandardExecution", ...
                lower(string(opt.Profile)) == "full", ...
            "RequireExactDataChannelExecution", true, ...
            "AssertPass", false, "PrintTable", false, ...
            "Verbose", logical(opt.Verbose)};
        nv = localOptionalNV(nv, "MinTransportBlocks", ...
            entryPolicy.MinTransportBlocks);
        nv = localOptionalNV(nv, "MaxTransportBlocks", ...
            entryPolicy.MaxTransportBlocks);
        nv = localOptionalNV(nv, "BatchSize", entryPolicy.BatchSize);
        nv = localOptionalNV(nv, "MaxConfidenceHalfWidth", ...
            entryPolicy.MaxConfidenceHalfWidth);
        result = sixgr.conformance.runFRCPoint(entryId, string(entry.condition.id), nv{:});
        rows(index).RequiredSNR_dB = double(result.RequiredSNR_dB);
        rows(index).MeasuredSNR_dB = double(result.MeasuredSNRAtTarget_dB);
        rows(index).Delta_dB = double(result.Delta_dB);
        rows(index).DataChannelExact = logical(result.DataChannelExecution.Exact);
        rows(index).FullStandardExecutionExact = logical(result.StandardExecution.Exact);
        rows(index).StatisticallyQualified = logical( ...
            result.ReferencePointStatisticallyQualified);
        rows(index).OneSidedReferencePass = logical(result.ReferencePointPass);
        rows(index).SymmetricRegressionPass = logical(result.ProjectDiagnosticPass);
        rows(index).SymmetricRegressionRequired = logical( ...
            opt.RequireSymmetricRegression);
        rows(index).SymmetricRegressionStatisticallyQualified = logical( ...
            result.ProjectDiagnosticStatisticallyQualified);
        rows(index).TransportBlocks = sum(double(result.Sweep.TransportBlocks));
        rows(index).BlockErrors = sum(double(result.Sweep.FailedTransportBlocks));
        if rows(index).FullStandardExecutionExact
            rows(index).EvidenceClass = ...
                "ACTUAL_FRC_FULL_STANDARD_TRUTH_EXECUTION";
        else
            rows(index).EvidenceClass = ...
                "ACTUAL_FRC_SELECTED_DATA_CHANNEL_TRUTH_EXECUTION";
        end
        rows(index).Pass = lower(string(opt.Profile)) == "full" && ...
            rows(index).FullStandardExecutionExact && ...
            rows(index).DataChannelExact && rows(index).StatisticallyQualified && ...
            rows(index).OneSidedReferencePass && ...
            (~rows(index).SymmetricRegressionRequired || ...
            rows(index).SymmetricRegressionPass);
        rows(index).Status = localState(rows(index).Pass);
        if ~rows(index).Pass
            rows(index).FailureReason = localResultFailure( ...
                result, opt.Profile, logical(opt.RequireSymmetricRegression));
        end
    catch ME
        rows(index).Pass = false;
        rows(index).Status = "FAIL";
        rows(index).EvidenceClass = "ACTUAL_FRC_EXECUTION_FAILURE";
        rows(index).FailureIdentifier = string(ME.identifier);
        rows(index).FailureReason = string(ME.message);
    end
    entryResults{index} = result;
    checkpoint = struct( ...
        "SchemaVersion", "sixgr.conformance.reference_checkpoint/v2", ...
        "EntryId", entryId, ...
        "IdentitySHA256", string(identitySHA256), ...
        "Identity", entryPolicy, ...
        "Row", rows(index), ...
        "ExecutionResult", result);
    sixgr.util.matSave(checkpointPath, checkpoint, "UseArtifactStore", false);
    localWritePartial(layout.ReportCSVDir, rows, index);
end

T = struct2table(rows);
if lower(string(opt.Profile)) == "full"
    outputPath = fullfile(layout.ReportCSVDir, "frc_reference_qualification.csv");
else
    outputPath = fullfile(layout.ReportCSVDir, "frc_reference_diagnostic.csv");
end
sixgr.util.csvWriteTable(outputPath, T, "PreserveSchema", true);
pointTable = localBuildReferencePointTable(entryResults, rows);
pointArtifacts = sixgr.conformance.publishReferenceQualificationArtifacts( ...
    runFolder, pointTable);
out = struct("Table", T, "OutputPath", string(outputPath), ...
    "Profile", lower(string(opt.Profile)), "AllPassed", all(T.Pass), ...
    "CatalogSHA256", string(catalogDigest), ...
    "CheckpointDirectory", string(checkpointDir), ...
    "EntryResults", {entryResults}, ...
    "PointTable", pointTable, ...
    "PointArtifacts", pointArtifacts, ...
    "ResumedEntries", entries(resumed), ...
    "ResumedCount", double(nnz(resumed)), ...
    "SourceIdentity", sourceIdentity);
end

function T = localBuildReferencePointTable(entryResults, summaryRows)
records = repmat(localEmptyReferencePointRow(), 0, 1);
for entryIndex = 1:numel(entryResults)
    result = entryResults{entryIndex};
    if ~(isstruct(result) && isscalar(result) && ...
            isfield(result, "Sweep") && istable(result.Sweep) && ...
            ~isempty(result.Sweep) && isfield(result, "PointDetails") && ...
            numel(result.PointDetails) == height(result.Sweep))
        continue;
    end
    sweep = result.Sweep;
    for pointIndex = 1:height(sweep)
        detail = result.PointDetails{pointIndex};
        row = localEmptyReferencePointRow();
        row.EntryId = string(result.EntryId);
        row.FRC = string(result.FRC);
        row.Condition = string(result.Condition);
        row.Direction = string(result.Direction);
        row.PhysicalChannel = string(result.PhysicalChannel);
        row.Profile = string(summaryRows(entryIndex).Profile);
        row.Metric = string(result.Requirement.metric);
        row.RequiredSNR_dB = double(result.RequiredSNR_dB);
        row.TargetFraction = double(result.Requirement.target_fraction);
        row.SNR_dB = double(sweep.SNR_dB(pointIndex));
        row.RequiredPoint = abs(row.SNR_dB - row.RequiredSNR_dB) <= 1e-10;
        row.MetricEstimate = double(sweep.MetricEstimate(pointIndex));
        row.ConfidenceLower = double(sweep.ConfidenceLower(pointIndex));
        row.ConfidenceUpper = double(sweep.ConfidenceUpper(pointIndex));
        row.OneSidedLower = double(sweep.OneSidedLower(pointIndex));
        row.OneSidedUpper = double(sweep.OneSidedUpper(pointIndex));
        row.TransportBlocks = double(sweep.TransportBlocks(pointIndex));
        row.DeliveredTransportBlocks = ...
            double(sweep.DeliveredTransportBlocks(pointIndex));
        row.FailedTransportBlocks = ...
            double(sweep.FailedTransportBlocks(pointIndex));
        row.Transmissions = double(sweep.Transmissions(pointIndex));
        row.PointEstimatePass = logical(sweep.PointEstimatePass(pointIndex));
        row.ConfidenceSupportsPass = ...
            logical(sweep.ConfidenceSupportsPass(pointIndex));
        row.ConfidenceQualificationEligible = ...
            logical(sweep.ConfidenceQualificationEligible(pointIndex));
        row.ConfidenceMethod = string(sweep.ConfidenceMethod(pointIndex));
        row.StopReason = string(sweep.StopReason(pointIndex));
        row.ExecutionBackend = string(result.ExecutionBackend);
        row.ApproximationMode = string(result.ApproximationMode);
        row.Source = string(result.Source);
        row.FullStandardExecutionExact = ...
            logical(result.StandardExecution.Exact);
        row.DataChannelExact = logical(result.DataChannelExecution.Exact);
        row.ProxyUsed = logical(sixgr.util.structGet( ...
            detail, "ProxyUsed", true));
        row.FallbackUsed = logical(sixgr.util.structGet( ...
            detail, "FallbackUsed", true));
        row.EvidenceClass = string(summaryRows(entryIndex).EvidenceClass);
        row.CatalogSHA256 = string(summaryRows(entryIndex).CatalogSHA256);
        records(end+1, 1) = row; %#ok<AGROW>
    end
end
T = struct2table(records, "AsArray", true);
end

function row = localEmptyReferencePointRow()
row = struct( ...
    "EntryId", "", "FRC", "", "Condition", "", ...
    "Direction", "", "PhysicalChannel", "", "Profile", "", ...
    "Metric", "", "RequiredSNR_dB", NaN, "TargetFraction", NaN, ...
    "SNR_dB", NaN, "RequiredPoint", false, ...
    "MetricEstimate", NaN, "ConfidenceLower", NaN, ...
    "ConfidenceUpper", NaN, "OneSidedLower", NaN, ...
    "OneSidedUpper", NaN, "TransportBlocks", 0, ...
    "DeliveredTransportBlocks", 0, "FailedTransportBlocks", 0, ...
    "Transmissions", 0, "PointEstimatePass", false, ...
    "ConfidenceSupportsPass", false, ...
    "ConfidenceQualificationEligible", false, ...
    "ConfidenceMethod", "", "StopReason", "", ...
    "ExecutionBackend", "", "ApproximationMode", "", ...
    "Source", "", "FullStandardExecutionExact", false, ...
    "DataChannelExact", false, "ProxyUsed", false, ...
    "FallbackUsed", false, "EvidenceClass", "", ...
    "CatalogSHA256", "");
end

function policy = localEntryPolicy(opt, entryId, catalogDigest, sourceIdentity)
policy = struct( ...
    "SchemaVersion", "sixgr.conformance.reference_checkpoint_identity/v1", ...
    "EntryId", string(entryId), ...
    "Profile", lower(string(opt.Profile)), ...
    "CatalogSHA256", string(catalogDigest), ...
    "GitCommit", string(sourceIdentity.GitCommit), ...
    "GitWorktreeDirty", logical(sourceIdentity.GitWorktreeDirty), ...
    "MATLABRelease", string(sourceIdentity.MATLABRelease), ...
    "Tolerance_dB", double(opt.Tolerance_dB), ...
    "ConfidenceLevel", double(opt.ConfidenceLevel), ...
    "MinimumBlockErrors", double(opt.MinimumBlockErrors), ...
    "RequireSymmetricRegression", logical(opt.RequireSymmetricRegression), ...
    "ParallelWorkers", double(opt.ParallelWorkers), ...
    "MinTransportBlocks", localEntrySamplingValue( ...
        opt.EntrySampling, entryId, "min_transport_blocks", ...
        opt.MinTransportBlocks), ...
    "MaxTransportBlocks", localEntrySamplingValue( ...
        opt.EntrySampling, entryId, "max_transport_blocks", ...
        opt.MaxTransportBlocks), ...
    "BatchSize", localEntrySamplingValue( ...
        opt.EntrySampling, entryId, "batch_size", opt.BatchSize), ...
    "MaxConfidenceHalfWidth", localEntrySamplingValue( ...
        opt.EntrySampling, entryId, "max_confidence_half_width", ...
        opt.MaxConfidenceHalfWidth));
end

function source = localSourceIdentity()
[commitStatus, commitText] = system("git rev-parse HEAD");
[dirtyStatus, dirtyText] = system( ...
    "git status --porcelain --untracked-files=normal");
if commitStatus == 0
    commit = strtrim(string(commitText));
else
    commit = "";
end
source = struct( ...
    "GitCommit", commit, ...
    "GitWorktreeDirty", dirtyStatus ~= 0 || ...
        strlength(strtrim(string(dirtyText))) > 0, ...
    "MATLABRelease", string(version("-release")));
end

function localValidateCheckpoint(checkpoint, checkpointPath, entryId, expectedHash)
required = ["SchemaVersion", "EntryId", "IdentitySHA256", "Identity", ...
    "Row", "ExecutionResult"];
missing = required(~isfield(checkpoint, cellstr(required)));
if ~isempty(missing)
    error("sixgr:conformance:QualificationCheckpointInvalid", ...
        "FRC checkpoint '%s' is missing field(s): %s.", ...
        checkpointPath, strjoin(missing, ", "));
end
if string(checkpoint.SchemaVersion) ~= ...
        "sixgr.conformance.reference_checkpoint/v2" || ...
        string(checkpoint.EntryId) ~= string(entryId) || ...
        ~isstruct(checkpoint.Row) || ~isscalar(checkpoint.Row)
    error("sixgr:conformance:QualificationCheckpointInvalid", ...
        "FRC checkpoint '%s' has an invalid schema or entry identity.", ...
        checkpointPath);
end
if lower(string(checkpoint.IdentitySHA256)) ~= lower(string(expectedHash))
    error("sixgr:conformance:QualificationCheckpointIdentityMismatch", ...
        ["FRC checkpoint '%s' was produced by a different catalog, source, " + ...
        "MATLAB release, or sampling policy. Use a new run folder or " + ...
        "explicitly disable resume."], checkpointPath);
end
expectedFields = string(fieldnames(localEmptyRow()));
if ~all(isfield(checkpoint.Row, cellstr(expectedFields)))
    error("sixgr:conformance:QualificationCheckpointInvalid", ...
        "FRC checkpoint '%s' does not contain the complete row schema.", ...
        checkpointPath);
end
if strlength(string(checkpoint.Row.FailureIdentifier)) == 0 && ...
        (~isstruct(checkpoint.ExecutionResult) || ...
        ~isscalar(checkpoint.ExecutionResult) || ...
        ~isfield(checkpoint.ExecutionResult, "ContractVersion") || ...
        string(checkpoint.ExecutionResult.EntryId) ~= string(entryId))
    error("sixgr:conformance:QualificationCheckpointInvalid", ...
        ["FRC checkpoint '%s' completed without an exception but does not " + ...
        "contain its full execution result."], checkpointPath);
end
end

function localWritePartial(reportCSVDir, rows, completedCount)
partial = struct2table(rows(1:completedCount));
partialPath = fullfile(reportCSVDir, ...
    "frc_reference_qualification.partial.csv");
sixgr.util.csvWriteTable(partialPath, partial, "PreserveSchema", true);
end

function token = localSafeToken(value)
token = regexprep(char(lower(string(value))), "[^a-z0-9_-]+", "_");
token = regexprep(token, "_+", "_");
token = regexprep(token, "^_+|_+$", "");
if isempty(token)
    error("sixgr:conformance:InvalidQualificationEntryToken", ...
        "Entry id '%s' cannot be converted to a checkpoint filename.", value);
end
end

function value = localExecutionProfile(profile)
if lower(string(profile)) == "full", value = "full"; else, value = "smoke"; end
end

function args = localOptionalNV(args, name, value)
if ~isempty(value), args(end+1:end+2) = {name, value}; end
end

function value = localEntrySamplingValue(raw, entryId, fieldName, defaultValue)
value = defaultValue;
if isempty(raw)
    return;
end
if iscell(raw)
    items = raw(:);
else
    items = num2cell(raw(:));
end
matches = false(numel(items),1);
for index = 1:numel(items)
    item = items{index};
    if ~isstruct(item) || ~isscalar(item) || ~isfield(item,"entry_id")
        error("sixgr:conformance:InvalidEntrySampling", ...
            "Each EntrySampling row must be a scalar struct with entry_id.");
    end
    matches(index) = string(item.entry_id) == string(entryId);
end
if nnz(matches) > 1
    error("sixgr:conformance:DuplicateEntrySampling", ...
        "EntrySampling contains duplicate rows for '%s'.", entryId);
end
if ~any(matches)
    return;
end
item = items{find(matches,1)};
if isfield(item, char(fieldName)) && ~isempty(item.(char(fieldName)))
    value = item.(char(fieldName));
end
end

function entry = localCatalogEntry(entries, id)
matches = false(numel(entries), 1);
for index = 1:numel(entries)
    candidate = localSequenceItem(entries, index);
    matches(index) = string(candidate.id) == string(id);
end
if nnz(matches) ~= 1
    error("sixgr:conformance:QualificationEntryNotFound", ...
        "Expected one catalog entry with id '%s'; found %d.", id, nnz(matches));
end
entry = localSequenceItem(entries, find(matches, 1));
end

function value = localSequenceItem(sequence, index)
if iscell(sequence), value = sequence{index}; else, value = sequence(index); end
end

function ids = localMandatoryAWGNEntries()
ids = ["dl_r_pdsch_1_1_4_fdd_awgn"; ...
    "dl_r_pdsch_1_3_6_fdd_atg_awgn"; ...
    "dl_r_pdsch_1_4_1_fdd_atg_awgn"; ...
    "ul_g_fr1_a3a_1_awgn"; ...
    "ul_g_fr1_a13_1_atg_awgn"];
end

function reason = localResultFailure(result, profile, requireSymmetricRegression)
parts = strings(0, 1);
if lower(string(profile)) ~= "full", parts(end+1,1) = "diagnostic_profile_not_qualification"; end %#ok<AGROW>
if ~logical(result.StandardExecution.Exact), parts(end+1,1) = "full_standard_execution_not_exact"; end %#ok<AGROW>
if ~logical(result.DataChannelExecution.Exact), parts(end+1,1) = "data_channel_not_exact"; end %#ok<AGROW>
if ~logical(result.StatisticallyQualified), parts(end+1,1) = "statistical_qualification_not_met"; end %#ok<AGROW>
if ~logical(result.ReferencePointPass), parts(end+1,1) = "one_sided_reference_point_failed"; end %#ok<AGROW>
if logical(requireSymmetricRegression) && ...
        ~logical(result.ProjectDiagnosticPass)
    parts(end+1,1) = "required_symmetric_reference_regression_failed"; %#ok<AGROW>
end
reason = strjoin(unique(parts, "stable"), ";");
end

function state = localState(pass)
if pass, state = "PASS"; else, state = "FAIL"; end
end

function row = localEmptyRow()
row = struct("EntryId","", "FRC","", "Condition","", "Required",true, ...
    "Profile","", "ExecutionAttempted",false, "DataChannelExact",false, ...
    "FullStandardExecutionExact",false, ...
    "StatisticallyQualified",false, "OneSidedReferencePass",false, ...
    "SymmetricRegressionRequired",false, ...
    "SymmetricRegressionStatisticallyQualified",false, ...
    "SymmetricRegressionPass",false, "RequiredSNR_dB",NaN, ...
    "MeasuredSNR_dB",NaN, "Delta_dB",NaN, "TransportBlocks",0, ...
    "BlockErrors",0, "Pass",false, "Status","NOT_EVALUATED", ...
    "EvidenceClass","", "CatalogSHA256","", "FailureIdentifier","", ...
    "FailureReason","");
end

function mustBeTextScalar(value)
if ~(ischar(value) || (isstring(value) && isscalar(value)))
    error("sixgr:conformance:InvalidQualificationOutputRoot", ...
        "runFolder must be a character vector or string scalar.");
end
end
