function [passed, failure, details] = validateReferenceQualificationTable(T, varargin)
%VALIDATEREFERENCEQUALIFICATIONTABLE Validate the canonical FRC gate table.
%
% 3GPP reference-point qualification is one-sided performance at the
% required SNR.  A symmetric measured-SNR crossing is an optional project
% regression.  Its measured SNR and delta are therefore required to be
% finite only on rows that explicitly set SymmetricRegressionRequired.
%
% Optional name/value inputs bind a persisted table to the scenario that
% requested it.  Without this binding, a stale or partial passing subset
% could satisfy a production reducer whose YAML requested more FRCs.

ip = inputParser;
ip.FunctionName = "sixgr.conformance.validateReferenceQualificationTable";
ip.addParameter("ExpectedEntryIds", strings(0,1), ...
    @(v) isstring(v) || iscellstr(v) || ischar(v));
ip.addParameter("CatalogEntryIds", strings(0,1), ...
    @(v) isstring(v) || iscellstr(v) || ischar(v));
ip.addParameter("ExpectedCatalogSHA256", "", ...
    @(v) ischar(v) || (isstring(v) && isscalar(v)));
ip.parse(varargin{:});
expectedEntryIds = strtrim(string(ip.Results.ExpectedEntryIds(:)));
expectedEntryIds = expectedEntryIds(strlength(expectedEntryIds) > 0);
catalogEntryIds = strtrim(string(ip.Results.CatalogEntryIds(:)));
catalogEntryIds = catalogEntryIds(strlength(catalogEntryIds) > 0);
expectedCatalogSHA256 = lower(strtrim(string( ...
    ip.Results.ExpectedCatalogSHA256)));

passed = false;
failure = "frc_reference_qualification_missing";
details = struct( ...
    "Evaluated", false, ...
    "RequiredRowCount", 0, ...
    "SymmetricRequiredRowCount", 0, ...
    "BaseContractPass", false, ...
    "EntryIdentityPass", false, ...
    "EntrySetPass", false, ...
    "CatalogMembershipPass", false, ...
    "CatalogBindingPass", false, ...
    "ExpectedEntryCount", double(numel(expectedEntryIds)), ...
    "SchemaContractPass", false, ...
    "TruthLineagePass", false, ...
    "SourceReproducibilityPass", false, ...
    "MetricConsistencyPass", false, ...
    "StatisticalContractPass", false, ...
    "DecisionConsistencyPass", false, ...
    "CrossingDisclosurePass", false, ...
    "SymmetricContractPass", false);
if ~(istable(T) && height(T) > 0)
    return;
end

columns = string(T.Properties.VariableNames);
requiredColumns = ["SchemaVersion","EntryId","FRC","Condition", ...
    "Required","ExperimentSeed", ...
    "ExecutionAttempted","Pass","FullStandardExecutionExact", ...
    "DataChannelExact","StatisticallyQualified", ...
    "OneSidedReferencePass","Profile","EvidenceClass", ...
    "SymmetricRegressionRequired","SymmetricRegressionPass", ...
    "SymmetricRegressionStatisticallyQualified", ...
    "Metric","Comparator","TargetFraction","PointEstimate", ...
    "ConfidenceLevel","OneSidedLower","OneSidedUpper", ...
    "PointEstimatePass","ObservedConfidenceBoundSupportsPass", ...
    "ConfidenceQualificationEligible", ...
    "RequiredQualificationTransportBlocks","ConfidenceMethod", ...
    "ConfidenceSamplingPlan","StatisticalUnit", ...
    "RequiredSNR_dB","MeasuredSNR_dB","Delta_dB", ...
    "MeasuredSNRAvailable","CrossingStatus", ...
    "CatalogSHA256","TransportBlocks","BlockErrors","Transmissions", ...
    "FailedTransmissionAttempts","SweepTransportBlocks", ...
    "SweepBlockErrors","SweepTransmissions", ...
    "SweepFailedTransmissionAttempts","ExecutionBackend", ...
    "ApproximationMode","Source","ProxyUsed","FallbackUsed", ...
    "Status","FailureIdentifier","FailureReason", ...
    "SourceGitCommit","SourceGitWorktreeDirty", ...
    "SourceMATLABRelease","SourceStateSHA256"];
if any(~ismember(requiredColumns, columns))
    failure = "frc_reference_qualification_schema_invalid";
    return;
end

[required, requiredValid] = localLogicalColumn(T.Required);
if ~all(requiredValid)
    failure = "frc_reference_qualification_schema_invalid";
    return;
end
if ~any(required)
    failure = "frc_reference_qualification_has_no_required_rows";
    return;
end
rows = T(required, :);
details.RequiredRowCount = height(rows);

logicalColumns = ["ExecutionAttempted","Pass", ...
    "FullStandardExecutionExact","DataChannelExact", ...
    "StatisticallyQualified","OneSidedReferencePass", ...
    "PointEstimatePass","ObservedConfidenceBoundSupportsPass", ...
    "ConfidenceQualificationEligible","MeasuredSNRAvailable", ...
    "ProxyUsed","FallbackUsed","SourceGitWorktreeDirty"];
if ismember("SymmetricRegressionRequired", columns)
    logicalColumns(end+1) = "SymmetricRegressionRequired";
end
if ismember("SymmetricRegressionPass", columns)
    logicalColumns(end+1) = "SymmetricRegressionPass";
end
if ismember("SymmetricRegressionStatisticallyQualified", columns)
    logicalColumns(end+1) = ...
        "SymmetricRegressionStatisticallyQualified";
end
logicalSchemaOK = true;
for name = logicalColumns
    [~, valid] = localLogicalColumn(rows.(char(name)));
    logicalSchemaOK = logicalSchemaOK && all(valid);
end
schemaContractPass = logicalSchemaOK && ...
    all(string(rows.SchemaVersion) == ...
    "sixgr.conformance.reference_qualification/v6");
details.SchemaContractPass = logical(schemaContractPass);
if ~schemaContractPass
    details.Evaluated = true;
    failure = "frc_reference_qualification_schema_invalid";
    return;
end

entryIds = strtrim(string(rows.EntryId));
frcIds = strtrim(string(rows.FRC));
conditions = strtrim(string(rows.Condition));
entryIdentityPass = all(strlength(entryIds) > 0) && ...
    all(strlength(frcIds) > 0) && all(strlength(conditions) > 0) && ...
    numel(unique(entryIds)) == height(rows) && ...
    numel(unique(frcIds + "|" + conditions)) == height(rows) && ...
    all(localLogicalColumn(rows.ExecutionAttempted));
details.EntryIdentityPass = logical(entryIdentityPass);

if isempty(expectedEntryIds)
    entrySetPass = true;
else
    entrySetPass = numel(unique(expectedEntryIds)) == ...
        numel(expectedEntryIds) && ...
        isequal(sort(entryIds), sort(expectedEntryIds));
end
details.EntrySetPass = logical(entrySetPass);
if ~entrySetPass
    details.Evaluated = true;
    failure = "frc_reference_qualification_entry_set_mismatch";
    return;
end

if isempty(catalogEntryIds)
    catalogMembershipPass = true;
else
    catalogMembershipPass = numel(unique(catalogEntryIds)) == ...
        numel(catalogEntryIds) && ...
        all(ismember(entryIds, catalogEntryIds)) && ...
        all(ismember(expectedEntryIds, catalogEntryIds));
end
details.CatalogMembershipPass = logical(catalogMembershipPass);
if ~catalogMembershipPass
    details.Evaluated = true;
    failure = "frc_reference_qualification_catalog_entry_missing";
    return;
end

symmetricRequired = false(height(rows), 1);
if ismember("SymmetricRegressionRequired", columns)
    symmetricRequired = localLogicalColumn( ...
        rows.SymmetricRegressionRequired);
end
details.SymmetricRequiredRowCount = nnz(symmetricRequired);
if any(symmetricRequired) && ...
        any(~ismember(["SymmetricRegressionPass", ...
        "SymmetricRegressionStatisticallyQualified"], columns))
    failure = "frc_reference_qualification_schema_invalid";
    return;
end

hashes = lower(strtrim(string(rows.CatalogSHA256)));
hashOK = arrayfun(@(x) strlength(x) == 64 && ...
    ~isempty(regexp(char(x), "^[0-9a-f]{64}$", "once")), hashes);
catalogBindingPass = all(hashOK) && numel(unique(hashes)) == 1;
if strlength(expectedCatalogSHA256) > 0
    expectedHashOK = strlength(expectedCatalogSHA256) == 64 && ...
        ~isempty(regexp(char(expectedCatalogSHA256), ...
        "^[0-9a-f]{64}$", "once"));
    catalogBindingPass = catalogBindingPass && expectedHashOK && ...
        all(hashes == expectedCatalogSHA256);
end
details.CatalogBindingPass = logical(catalogBindingPass);
requiredSNR = localNumericColumn(rows.RequiredSNR_dB);
experimentSeed = localNumericColumn(rows.ExperimentSeed);
targetFraction = localNumericColumn(rows.TargetFraction);
pointEstimate = localNumericColumn(rows.PointEstimate);
confidenceLevel = localNumericColumn(rows.ConfidenceLevel);
oneSidedLower = localNumericColumn(rows.OneSidedLower);
oneSidedUpper = localNumericColumn(rows.OneSidedUpper);
requiredQualificationTB = localNumericColumn( ...
    rows.RequiredQualificationTransportBlocks);
transportBlocks = localNumericColumn(rows.TransportBlocks);
blockErrors = localNumericColumn(rows.BlockErrors);
transmissions = localNumericColumn(rows.Transmissions);
failedAttempts = localNumericColumn(rows.FailedTransmissionAttempts);
sweepTransportBlocks = localNumericColumn(rows.SweepTransportBlocks);
sweepBlockErrors = localNumericColumn(rows.SweepBlockErrors);
sweepTransmissions = localNumericColumn(rows.SweepTransmissions);
sweepFailedAttempts = localNumericColumn( ...
    rows.SweepFailedTransmissionAttempts);
baseNumericOK = isfinite(requiredSNR) & ...
    isfinite(experimentSeed) & experimentSeed >= 0 & ...
    experimentSeed == fix(experimentSeed) & ...
    isfinite(targetFraction) & targetFraction >= 0 & targetFraction <= 1 & ...
    isfinite(pointEstimate) & pointEstimate >= 0 & pointEstimate <= 1 & ...
    isfinite(confidenceLevel) & confidenceLevel > 0 & confidenceLevel < 1 & ...
    isfinite(oneSidedLower) & oneSidedLower >= 0 & ...
    isfinite(oneSidedUpper) & oneSidedUpper <= 1 & ...
    oneSidedLower <= pointEstimate & pointEstimate <= oneSidedUpper & ...
    isfinite(requiredQualificationTB) & requiredQualificationTB >= 1 & ...
    requiredQualificationTB == fix(requiredQualificationTB) & ...
    isfinite(transportBlocks) & transportBlocks > 0 & ...
    transportBlocks == fix(transportBlocks) & ...
    isfinite(transmissions) & transmissions >= transportBlocks & ...
    transmissions == fix(transmissions) & ...
    isfinite(blockErrors) & blockErrors >= 0 & ...
    blockErrors <= transportBlocks & blockErrors == fix(blockErrors) & ...
    isfinite(failedAttempts) & failedAttempts >= 0 & ...
    failedAttempts == fix(failedAttempts) & ...
    failedAttempts == transmissions - (transportBlocks - blockErrors) & ...
    isfinite(sweepTransportBlocks) & ...
    sweepTransportBlocks >= transportBlocks & ...
    sweepTransportBlocks == fix(sweepTransportBlocks) & ...
    isfinite(sweepBlockErrors) & sweepBlockErrors >= blockErrors & ...
    sweepBlockErrors <= sweepTransportBlocks & ...
    sweepBlockErrors == fix(sweepBlockErrors) & ...
    isfinite(sweepTransmissions) & ...
    sweepTransmissions >= transmissions & ...
    sweepTransmissions == fix(sweepTransmissions) & ...
    isfinite(sweepFailedAttempts) & ...
    sweepFailedAttempts >= failedAttempts & ...
    sweepFailedAttempts == fix(sweepFailedAttempts) & ...
    sweepFailedAttempts == sweepTransmissions - ...
        (sweepTransportBlocks - sweepBlockErrors);

metric = lower(strtrim(string(rows.Metric)));
comparator = lower(strtrim(string(rows.Comparator)));
metricKindOK = (metric == "block_error_rate" & ...
    comparator == "less_equal") | ...
    (metric == "fraction_of_maximum_throughput" & ...
    comparator == "greater_equal");
expectedEstimate = nan(height(rows), 1);
bler = metric == "block_error_rate";
throughput = metric == "fraction_of_maximum_throughput";
expectedEstimate(bler) = blockErrors(bler) ./ transportBlocks(bler);
expectedEstimate(throughput) = ...
    (transportBlocks(throughput) - blockErrors(throughput)) ./ ...
    transmissions(throughput);
metricTolerance = 64 .* eps(max(1, abs(expectedEstimate)));
metricConsistencyPass = all(metricKindOK & baseNumericOK & ...
    abs(pointEstimate - expectedEstimate) <= metricTolerance);
details.MetricConsistencyPass = logical(metricConsistencyPass);

pointEstimateExpected = (comparator == "less_equal" & ...
    pointEstimate <= targetFraction) | ...
    (comparator == "greater_equal" & pointEstimate >= targetFraction);
confidenceExpected = (comparator == "less_equal" & ...
    oneSidedUpper <= targetFraction) | ...
    (comparator == "greater_equal" & ...
    oneSidedLower >= targetFraction);
pointEstimateReported = localLogicalColumn(rows.PointEstimatePass);
confidenceReported = localLogicalColumn( ...
    rows.ObservedConfidenceBoundSupportsPass);
confidenceEligible = localLogicalColumn( ...
    rows.ConfidenceQualificationEligible);
dataExact = localLogicalColumn(rows.DataChannelExact);
statisticallyQualified = localLogicalColumn(rows.StatisticallyQualified);
oneSidedReferencePass = localLogicalColumn(rows.OneSidedReferencePass);
expectedStatisticallyQualified = dataExact & confidenceEligible & ...
    transportBlocks >= requiredQualificationTB;
expectedReferencePass = expectedStatisticallyQualified & ...
    pointEstimateExpected & confidenceExpected;
statisticalContractPass = all(confidenceEligible & ...
    transportBlocks >= requiredQualificationTB & ...
    statisticallyQualified == expectedStatisticallyQualified & ...
    pointEstimateReported == pointEstimateExpected & ...
    confidenceReported == confidenceExpected & ...
    oneSidedReferencePass == expectedReferencePass & ...
    strlength(strtrim(string(rows.ConfidenceMethod))) > 0 & ...
    strlength(strtrim(string(rows.ConfidenceSamplingPlan))) > 0 & ...
    strtrim(string(rows.StatisticalUnit)) == ...
        "independently_sampled_transport_block");
details.StatisticalContractPass = logical(statisticalContractPass);

proxyUsed = localLogicalColumn(rows.ProxyUsed);
fallbackUsed = localLogicalColumn(rows.FallbackUsed);
truthLineagePass = all(~proxyUsed & ~fallbackUsed & ...
    lower(strtrim(string(rows.ApproximationMode))) == "none" & ...
    strlength(strtrim(string(rows.ExecutionBackend))) > 0 & ...
    strlength(strtrim(string(rows.Source))) > 0 & ...
    string(rows.EvidenceClass) == ...
        "ACTUAL_FRC_FULL_STANDARD_TRUTH_EXECUTION");
details.TruthLineagePass = logical(truthLineagePass);

sourceCommit = lower(strtrim(string(rows.SourceGitCommit)));
sourceState = lower(strtrim(string(rows.SourceStateSHA256)));
sourceDirty = localLogicalColumn(rows.SourceGitWorktreeDirty);
commitOK = arrayfun(@(x) strlength(x) == 40 && ...
    ~isempty(regexp(char(x), "^[0-9a-f]{40}$", "once")), sourceCommit);
sourceStateOK = arrayfun(@(x) strlength(x) == 64 && ...
    ~isempty(regexp(char(x), "^[0-9a-f]{64}$", "once")), sourceState);
sourceReproducibilityPass = all(commitOK & sourceStateOK & ...
    ~sourceDirty & strlength(strtrim(string(rows.SourceMATLABRelease))) > 0);
details.SourceReproducibilityPass = logical(sourceReproducibilityPass);

reportedPass = localLogicalColumn(rows.Pass);
fullExact = localLogicalColumn(rows.FullStandardExecutionExact);
expectedPass = fullExact & expectedReferencePass & ...
    ~proxyUsed & ~fallbackUsed & ~sourceDirty & ...
    lower(strtrim(string(rows.Profile))) == "full" & ...
    lower(strtrim(string(rows.ApproximationMode))) == "none";
decisionConsistencyPass = all(reportedPass == expectedPass & ...
    reportedPass & upper(strtrim(string(rows.Status))) == "PASS" & ...
    strlength(strtrim(string(rows.FailureIdentifier))) == 0 & ...
    strlength(strtrim(string(rows.FailureReason))) == 0);
details.DecisionConsistencyPass = logical(decisionConsistencyPass);
baseContractPass = ...
    entryIdentityPass && entrySetPass && catalogMembershipPass && ...
    catalogBindingPass && schemaContractPass && ...
    metricConsistencyPass && statisticalContractPass && ...
    truthLineagePass && sourceReproducibilityPass && ...
    decisionConsistencyPass && ...
    all(fullExact) && all(dataExact) && ...
    all(statisticallyQualified) && all(oneSidedReferencePass) && ...
    all(lower(strtrim(string(rows.Profile))) == "full") && ...
    all(baseNumericOK);

symmetricContractPass = true;
if any(symmetricRequired)
    measured = localNumericColumn(rows.MeasuredSNR_dB);
    delta = localNumericColumn(rows.Delta_dB);
    symmetricPass = localLogicalColumn(rows.SymmetricRegressionPass);
    symmetricQualified = localLogicalColumn( ...
        rows.SymmetricRegressionStatisticallyQualified);
    symmetricContractPass = all(~symmetricRequired | ...
        (isfinite(measured) & isfinite(delta) & ...
        symmetricPass & symmetricQualified));
end

measured = localNumericColumn(rows.MeasuredSNR_dB);
delta = localNumericColumn(rows.Delta_dB);
measuredAvailable = localLogicalColumn(rows.MeasuredSNRAvailable);
crossingStatus = strtrim(string(rows.CrossingStatus));
crossingDisclosurePass = all(strlength(crossingStatus) > 0) && ...
    all(measuredAvailable == (isfinite(measured) & isfinite(delta)));

details.Evaluated = true;
details.BaseContractPass = logical(baseContractPass);
details.CrossingDisclosurePass = logical(crossingDisclosurePass);
details.SymmetricContractPass = logical( ...
    symmetricContractPass && crossingDisclosurePass);
passed = logical(baseContractPass && symmetricContractPass && ...
    crossingDisclosurePass);
if passed
    failure = "";
else
    failure = "frc_reference_qualification_required_row_failed";
end
end

function [values, valid] = localLogicalColumn(raw)
if islogical(raw)
    values = raw(:);
    valid = true(size(values));
elseif isnumeric(raw)
    numeric = double(raw(:));
    valid = isfinite(numeric) & ismember(numeric, [0 1]);
    values = numeric == 1;
else
    token = lower(strtrim(string(raw(:))));
    trueTokens = ["1","true","yes","on","pass","passed"];
    falseTokens = ["0","false","no","off","fail","failed"];
    valid = ismember(token, [trueTokens,falseTokens]);
    values = ismember(token, ["1","true","yes","on","pass","passed"]);
end
end

function values = localNumericColumn(raw)
if isnumeric(raw) || islogical(raw)
    values = double(raw(:));
else
    values = str2double(string(raw(:)));
end
end
