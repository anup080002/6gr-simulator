function [grid, evidence] = materializeFRCDownlinkAuxiliary( ...
        entry, carrier, cfg, grid, pdsch, pdschPrecoder, seed)
%MATERIALIZEFRCDOWNLINKAUXILIARY Add the TS 38.101-4 common DL waveform.
%
% This function operates on the same physical-port grid that carries the
% PDSCH. It materializes the per-slot PDCCH/PDCCH-DMRS, the slot-zero
% acquisition CSI-RS resources, and Annex A.5.1.1 OP.1. Tracking CSI-RS is
% mapped by runFRCPoint before this function is called because those REs
% are part of the PDSCH rate-matching contract.
%
% No configured-value or proxy evidence is returned: every count and hash
% below is calculated from the grid actually handed to OFDM modulation.

arguments
    entry (1,1) struct
    carrier
    cfg (1,1) struct
    grid {mustBeNumeric}
    pdsch
    pdschPrecoder {mustBeNumeric}
    seed (1,1) double {mustBeFinite,mustBeInteger,mustBeNonnegative}
end

if string(entry.direction) ~= "downlink"
    error("sixgr:conformance:InvalidAuxiliaryDirection", ...
        "The TS 38.101-4 auxiliary downlink waveform requires a DL FRC.");
end
if ~isfield(entry, "standard_downlink_timeline")
    error("sixgr:conformance:MissingStandardDownlinkTimeline", ...
        "The FRC catalog entry has no standard_downlink_timeline authority.");
end
plan = entry.standard_downlink_timeline;
if ~logical(plan.enabled)
    error("sixgr:conformance:StandardDownlinkTimelineDisabled", ...
        "The catalog disables the standard downlink timeline.");
end

k = double(carrier.NSizeGrid) * 12;
l = double(carrier.SymbolsPerSlot);
nTx = double(entry.mimo.tx_antennas);
if ismatrix(grid)
    grid = reshape(grid, size(grid,1), size(grid,2), 1);
end
if size(grid,1) ~= k || size(grid,2) ~= l || size(grid,3) ~= nTx
    error("sixgr:conformance:InvalidAuxiliaryGrid", ...
        "Physical grid size %s differs from required [%d %d %d].", ...
        mat2str(size(grid)), k, l, nTx);
end

slot = localAbsoluteSlot(carrier);
beforeHash = sixgr.phy.waveform.WaveformHash.numeric(grid);
[grid, pdcchEvidence, pdcchMap] = localMapPDCCH( ...
    entry, carrier, cfg, grid, pdsch, seed);
[grid, acquisitionEvidence, reservedMask] = localMapAcquisitionCSIRS( ...
    entry, carrier, grid);
[grid, ocngEvidence] = localMapOCNG( ...
    entry, carrier, grid, pdsch, pdschPrecoder, pdcchMap, ...
    reservedMask, seed + 7919);

evidence = struct( ...
    "ContractVersion", "sixgr_ts38101_4_common_dl_slot/v1", ...
    "StandardReference", string(plan.standard_reference), ...
    "AbsoluteSlot", slot, ...
    "SlotWithinPeriod", mod(slot, double(plan.period_slots)), ...
    "PhysicalTransmitPorts", nTx, ...
    "PDCCH", pdcchEvidence, ...
    "AcquisitionCSIRS", acquisitionEvidence, ...
    "OCNG", ocngEvidence, ...
    "InputGridSHA256", string(beforeHash), ...
    "OutputGridSHA256", string( ...
        sixgr.phy.waveform.WaveformHash.numeric(grid)), ...
    "MeasuredFromMaterializedGrid", true, ...
    "ProxyUsed", false, ...
    "FallbackUsed", false);
end

function [grid, evidence, map] = localMapPDCCH( ...
        entry, carrier, cfg, grid, pdsch, seed)
plan = entry.standard_downlink_timeline.pdcch;
if ~logical(plan.enabled)
    error("sixgr:conformance:StandardPDCCHDisabled", ...
        "The standard downlink timeline requires per-slot PDCCH.");
end

pdcchCfg = cfg;
pdcchCfg.phy.pdcch.enable = true;
pdcchCfg.phy.pdcch.dmrs.enable = true;
pdcchCfg.phy.pdcch.KBits = 64;
pdcchCfg.phy.pdcch.coreset.id = 0;
pdcchCfg.phy.pdcch.coreset.duration = numel(plan.symbol_indices);
pdcchCfg.phy.pdcch.coreset.frequencyResources = ...
    ones(1, double(plan.coreset_prbs) / 6);
pdcchCfg.phy.pdcch.coreset.mappingType = ...
    char(string(plan.cce_to_reg_mapping));
pdcchCfg.phy.pdcch.coreset.regBundleSize = double(plan.reg_bundle_size);
pdcchCfg.phy.pdcch.coreset.shiftIndex = double(carrier.NCellID);
pdcchCfg.phy.pdcch.searchSpace.id = 1;
pdcchCfg.phy.pdcch.searchSpace.startSymbol = ...
    double(plan.symbol_indices(1));
pdcchCfg.phy.pdcch.searchSpace.slotPeriodAndOffset = [1 0];
pdcchCfg.phy.pdcch.searchSpace.duration = 1;
pdcchCfg.phy.pdcch.searchSpace.numCandidates = [0 0 0 1 0];
pdcchCfg.phy.pdcch.aggregationLevel = double(plan.aggregation_level);
pdcchCfg.phy.pdcch.rnti = 1;
pdcchCfg.phy.pdcch.scramblingRNTI = 1;

[dci, dciContext, parsedDCI] = localBuildContextualDCI11( ...
    entry, carrier, pdsch, plan);
pdcchCfg.phy.pdcch.KBits = numel(dci.Bits);
grant = struct("DCI", dci);

[logicalTx, info] = sixgr.phy.dl.PDCCH_Tx(pdcchCfg, ...
    "Carrier", carrier, "NumTxAnt", 1, "OFDMModulate", false, ...
    "Grant", grant, "RNTI", 1, ...
    "PDCCHScramblingRNTI", 1, "NCellID", double(carrier.NCellID));
logicalGrid = reshape(logicalTx.Grid, size(logicalTx.Grid,1), ...
    size(logicalTx.Grid,2));
active = find(abs(logicalGrid) > 0);
[subcarrier, symbol] = ind2sub(size(logicalGrid), active);
duration = numel(plan.symbol_indices);
rb = floor((double(subcarrier) - 1) / 12);
reg = rb .* duration + (double(symbol) - 1);
bundle = floor(reg / double(plan.reg_bundle_size)) + 1;
bundleCount = ceil(double(plan.coreset_prbs) * duration / ...
    double(plan.reg_bundle_size));
if any(bundle > bundleCount)
    error("sixgr:conformance:PDCCHREGBundleOverflow", ...
        "PDCCH resource mapping exceeds the configured CORESET bundles.");
end
precoders = localRankOnePrecoders(cfg, ...
    double(entry.mimo.tx_antennas), bundleCount, seed);

for item = 1:numel(active)
    value = logicalGrid(active(item));
    page = precoders(:, bundle(item));
    existing = reshape(grid(subcarrier(item), symbol(item), :), [], 1);
    if any(abs(existing) > 1e-12)
        error("sixgr:conformance:PDCCHCollision", ...
            "PDCCH collides at subcarrier %d, symbol %d, slot %d.", ...
            subcarrier(item)-1, symbol(item)-1, localAbsoluteSlot(carrier));
    end
    grid(subcarrier(item), symbol(item), :) = reshape(value .* page, 1,1,[]);
end

map = struct( ...
    "ControlRBCount", double(plan.coreset_prbs), ...
    "ControlSymbols", double(plan.symbol_indices(:).'), ...
    "REGBundleSize", double(plan.reg_bundle_size), ...
    "Precoders", precoders);
evidence = struct( ...
    "Materialized", true, ...
    "MonitoringSlots", string(plan.monitoring_slots), ...
    "DCIFormat", string(plan.dci_format), ...
    "DCIPayloadSource", string(info.DCIPayloadSource), ...
    "DCIPayloadBits", double(info.K), ...
    "DCIContextDigest", string(dciContext.Digest), ...
    "DCIPayloadHash", string(dci.PayloadHash), ...
    "DCIContextDerived", true, ...
    "DCIEncodeParseRoundTrip", isequal(int8(dci.Bits(:)), ...
        int8(parsedDCI.Bits(:))), ...
    "ScheduledPRBStart", double(parsedDCI.Fields.prb_start), ...
    "ScheduledNumPRB", double(parsedDCI.Fields.num_prb), ...
    "ScheduledSymbolStart", double(parsedDCI.Fields.symbol_start), ...
    "ScheduledNumSymbols", double(parsedDCI.Fields.num_symbols), ...
    "ScheduledMCS", double(parsedDCI.Fields.mcs), ...
    "ScheduledLayers", double(dci.Fields.antenna_ports) + 1, ...
    "AggregationLevel", double(plan.aggregation_level), ...
    "CandidateCount", double(plan.candidate_count), ...
    "CORESETPRBs", double(plan.coreset_prbs), ...
    "ControlSymbols", double(plan.symbol_indices(:).'), ...
    "PDCCHRE", double(info.NumPDCCHRE), ...
    "DMRSRE", double(info.NumDMRSRE), ...
    "PhysicalMappedRE", numel(active), ...
    "REGBundleCount", bundleCount, ...
    "PrecoderPower", sum(abs(precoders).^2,1), ...
    "GridSHA256", string( ...
        sixgr.phy.waveform.WaveformHash.numeric(logicalGrid)));
end

function [dci, context, parsed] = localBuildContextualDCI11( ...
        entry, carrier, pdsch, plan)
if string(plan.dci_format) ~= "1_1"
    error("sixgr:conformance:UnsupportedStandardDCIFormat", ...
        "The Release-18 FRC timeline requires DCI 1_1; catalog requested %s.", ...
        string(plan.dci_format));
end
nGrid = double(carrier.NSizeGrid);
prbSet = double(pdsch.PRBSet(:).');
if isempty(prbSet) || any(diff(prbSet) ~= 1)
    error("sixgr:conformance:NoncontiguousFRCPRBAllocation", ...
        "Contextual DCI 1_1 requires one contiguous FRC PRB allocation.");
end
symbolAllocation = double(pdsch.SymbolAllocation(:).');
if ~isequal(symbolAllocation, [2 12])
    error("sixgr:conformance:UnsupportedFRCTDRA", ...
        ["The installed TS 38.101-4 FRC DCI context maps TDRA index 0 " ...
         "to symbols [2 12]; the actual PDSCH requested %s."], ...
        mat2str(symbolAllocation));
end
mcs = double(entry.coding.mcs_index);
if ~(isscalar(mcs) && isfinite(mcs) && mcs == fix(mcs) && ...
        mcs >= 0 && mcs <= 31)
    error("sixgr:conformance:InvalidFRCDCI11MCS", ...
        "FRC mcs_index must be an integer in [0,31] for DCI 1_1.");
end
layers = double(entry.mimo.layers);
if ~(isscalar(layers) && ismember(layers, 1:4))
    error("sixgr:conformance:InvalidFRCDCI11Layers", ...
        "FRC DCI 1_1 supports the catalog layer set 1 through 4.");
end

contextCfg = struct( ...
    "NSizeGrid", nGrid, ...
    "RNTIType", "C-RNTI", ...
    "RNTIValue", 1, ...
    "SearchSpaceType", "USS", ...
    "SearchSpaceId", 1, ...
    "CORESETId", 0, ...
    "MonitoredFormats", "1_1", ...
    "ConfigurationEpoch", 1);
context = sixgr.phy.pdcch.DCIContext.fromLegacy(contextCfg, "1_1");
dci = sixgr.phy.pdcch.buildDCI11DownlinkAssignment( ...
    contextCfg, ...
    "PRBStart", prbSet(1), ...
    "NumPRB", numel(prbSet), ...
    "MCS", mcs, ...
    "HARQProcess", 0, ...
    "NumLayers", layers, ...
    "PMI", 0);
parsed = sixgr.phy.pdcch.DCIParser.parse(dci.Bits, context);
if parsed.ContextDigest ~= dci.ContextDigest || ...
        parsed.Fields.prb_start ~= prbSet(1) || ...
        parsed.Fields.num_prb ~= numel(prbSet) || ...
        parsed.Fields.symbol_start ~= symbolAllocation(1) || ...
        parsed.Fields.num_symbols ~= symbolAllocation(2) || ...
        parsed.Fields.mcs ~= mcs || ...
        parsed.Fields.antenna_ports + 1 ~= layers
    error("sixgr:conformance:FRCContextualDCIRoundTripMismatch", ...
        "Contextual DCI 1_1 does not reproduce the active FRC PDSCH grant.");
end
end

function precoders = localRankOnePrecoders(cfg, nTx, count, seed)
if nTx == 1
    precoders = ones(1, count);
    return;
end
[candidates, ~] = sixgr.phy.dl.pmiCodebookCandidates( ...
    cfg, 1, nTx, "Mode", "type1_su_mimo");
if isempty(candidates)
    error("sixgr:conformance:EmptyPDCCHPrecoderCodebook", ...
        "No Type-I rank-one PDCCH precoder exists for %d ports.", nTx);
end
stream = RandStream("mt19937ar", "Seed", localSeed(seed));
selection = randi(stream, numel(candidates), [1 count]);
precoders = complex(zeros(nTx, count));
for index = 1:count
    page = double(candidates(selection(index)).W);
    if ~isequal(size(page), [nTx 1])
        error("sixgr:conformance:PDCCHPrecoderShapeMismatch", ...
            "PDCCH Type-I page has size %s; expected [%d 1].", ...
            mat2str(size(page)), nTx);
    end
    power = real(page' * page);
    if ~(isfinite(power) && abs(power - 1) <= 1e-12)
        error("sixgr:conformance:PDCCHPrecoderPowerMismatch", ...
            "PDCCH precoder power is %.16g, expected one.", power);
    end
    precoders(:,index) = page;
end
end

function [grid, evidence, reservedMask] = localMapAcquisitionCSIRS( ...
        entry, carrier, grid)
plan = entry.standard_downlink_timeline;
slot = mod(localAbsoluteSlot(carrier), double(plan.period_slots));
k = size(grid,1);
l = size(grid,2);
reservedMask = false(k,l);
if slot ~= double(plan.acquisition_nzp_csirs.slot_offset)
    evidence = struct("Materialized", false, "Applicable", false, ...
        "Reason", "not_acquisition_slot", "NZPRE", 0, "ZPRE", 0);
    return;
end

nTx = double(entry.mimo.tx_antennas);
nzp = plan.acquisition_nzp_csirs;
row = double(nzp.row_by_port_count(nTx));
cdm = string(nzp.cdm_type_by_port_count(nTx));
if cdm == "unsupported"
    error("sixgr:conformance:UnsupportedAcquisitionCSIRSPortCount", ...
        "No catalog-owned acquisition CSI-RS mapping exists for %d ports.", nTx);
end
nzpCfg = nrCSIRSConfig;
nzpCfg.CSIRSType = "nzp";
nzpCfg.RowNumber = row;
nzpCfg.Density = char(string(nzp.density));
nzpCfg.SubcarrierLocations = double(nzp.first_subcarrier_index);
nzpCfg.SymbolLocations = double(nzp.first_symbol_index);
nzpCfg.RBOffset = double(nzp.rb_offset);
nzpCfg.NumRB = double(nzp.num_rbs);
nzpCfg.NID = 0;
nzpCfg.CSIRSPeriod = [double(nzp.period_slots), double(nzp.slot_offset)];
nzpIndices = double(nrCSIRSIndices(carrier, nzpCfg));
nzpSymbols = nrCSIRS(carrier, nzpCfg);
cdmGroupSize = localCDMGroupSize(cdm);
nzpSymbols = nzpSymbols ./ sqrt(cdmGroupSize);
nzpGrid = nrResourceGrid(carrier, nTx);
nzpGrid(nzpIndices) = nzpSymbols;
collision = any((abs(nzpGrid) > 0) & (abs(grid) > 1e-12), "all");
if collision
    error("sixgr:conformance:AcquisitionCSIRSCollision", ...
        "NZP acquisition CSI-RS collides with an existing slot-zero signal.");
end
grid = grid + nzpGrid;

zp = plan.acquisition_zp_csirs;
zpCfg = nrCSIRSConfig;
zpCfg.CSIRSType = "zp";
zpCfg.RowNumber = double(zp.row_number);
zpCfg.Density = char(string(zp.density));
zpCfg.SubcarrierLocations = double(zp.first_subcarrier_index);
zpCfg.SymbolLocations = double(zp.first_symbol_index);
zpCfg.RBOffset = double(zp.rb_offset);
zpCfg.NumRB = double(zp.num_rbs);
zpCfg.CSIRSPeriod = [double(zp.period_slots), double(zp.slot_offset)];
zpIndices = double(nrCSIRSIndices(carrier, zpCfg));
zpProbe = nrResourceGrid(carrier, double(zp.port_count));
zpProbe(zpIndices) = 1;
reservedMask = any(zpProbe ~= 0, 3);
if any(abs(grid(repmat(reservedMask,1,1,size(grid,3)))) > 1e-12)
    error("sixgr:conformance:ZPCSIRSReservationCollision", ...
        "ZP acquisition CSI-RS reservation collides with a mapped signal.");
end

evidence = struct( ...
    "Materialized", true, "Applicable", true, "Reason", "", ...
    "NZPRow", row, "NZPPorts", nTx, "NZPCDMType", cdm, ...
    "NZPCDMGroupSize", cdmGroupSize, ...
    "NZPEPRERelativeToSSS_dB", -10*log10(cdmGroupSize), ...
    "NZPRE", nnz(abs(nzpGrid) > 0), ...
    "NZPDirectPhysicalPortMapping", logical( ...
        nzp.direct_port_to_physical_antenna_mapping), ...
    "NZPGridSHA256", string( ...
        sixgr.phy.waveform.WaveformHash.numeric(nzpGrid)), ...
    "ZPRow", double(zp.row_number), ...
    "ZPPorts", double(zp.port_count), ...
    "ZPRE", nnz(reservedMask), ...
    "ZPReservationSHA256", string( ...
        sixgr.phy.waveform.WaveformHash.numeric(double(reservedMask))));
end

function [grid, evidence] = localMapOCNG( ...
        entry, carrier, grid, pdsch, pdschPrecoder, pdcchMap, ...
        reservedMask, seed)
plan = entry.standard_downlink_timeline.ocng;
if ~logical(plan.enabled)
    error("sixgr:conformance:StandardOCNGDisabled", ...
        "Annex A.5.1.1 OP.1 is disabled in the catalog.");
end
stream = RandStream("mt19937ar", "Seed", localSeed(seed));
k = size(grid,1);
l = size(grid,2);
nTx = size(grid,3);
nLayers = double(entry.mimo.layers);
occupied = any(abs(grid) > 1e-12, 3);

controlMask = false(k,l);
controlRB = double(pdcchMap.ControlRBCount);
controlSymbols = double(pdcchMap.ControlSymbols) + 1;
controlMask(1:12*controlRB, controlSymbols) = true;
controlFill = find(controlMask & ~occupied & ~reservedMask);
[controlK, controlL] = ind2sub([k l], controlFill);
duration = numel(controlSymbols);
controlRBIndex = floor((controlK - 1) / 12);
controlREG = controlRBIndex .* duration + (controlL - 1);
controlBundle = floor(controlREG / double(pdcchMap.REGBundleSize)) + 1;
for item = 1:numel(controlFill)
    symbol = localQPSK(stream, 1);
    w = pdcchMap.Precoders(:, controlBundle(item));
    grid(controlK(item), controlL(item), :) = reshape(symbol .* w,1,1,[]);
end

occupied = any(abs(grid) > 1e-12, 3);
dataMask = true(k,l);
dataMask(:,controlSymbols) = false;
dataFill = find(dataMask & ~occupied & ~reservedMask);
[dataK, dataL] = ind2sub([k l], dataFill);
for item = 1:numel(dataFill)
    layerSymbols = localQPSK(stream, nLayers);
    w = localPDSCHPrecoderForRB( ...
        pdschPrecoder, pdsch, floor((dataK(item)-1)/12), nTx, nLayers);
    physical = w * layerSymbols;
    grid(dataK(item), dataL(item), :) = reshape(physical,1,1,[]);
end

evidence = struct( ...
    "Materialized", true, ...
    "Pattern", string(plan.pattern), ...
    "Content", string(plan.content), ...
    "ControlRegionRE", numel(controlFill), ...
    "DataRegionRE", numel(dataFill), ...
    "TotalFilledRE", numel(controlFill) + numel(dataFill), ...
    "ControlTransmission", string(plan.control_region_transmission), ...
    "DataTransmission", string(plan.data_region_transmission), ...
    "ReservedREExcluded", nnz(reservedMask));
end

function w = localPDSCHPrecoderForRB(precoder, pdsch, rb, nTx, nLayers)
if isempty(precoder)
    if nTx == 1 && nLayers == 1
        w = 1;
        return;
    end
    error("sixgr:conformance:MissingOCNGPDSCHPrecoder", ...
        "OP.1 data-region mapping requires the actual PDSCH precoder.");
end
if ismatrix(precoder) || size(precoder,3) == 1
    w = reshape(precoder, size(precoder,1), size(precoder,2));
else
    pageCount = size(precoder,3);
    rbMin = min(double(pdsch.PRBSet));
    rbMax = max(double(pdsch.PRBSet));
    page = floor((double(rb) - rbMin) * pageCount / (rbMax - rbMin + 1)) + 1;
    page = min(max(page,1),pageCount);
    w = precoder(:,:,page);
end

if ~isequal(size(w), [nTx nLayers])
    error("sixgr:conformance:OCNGPDSCHPrecoderShapeMismatch", ...
        "OP.1 precoder size %s differs from [%d %d].", ...
        mat2str(size(w)), nTx, nLayers);
end
power = real(trace(w*w'));
if ~(isfinite(power) && abs(power - 1) <= 1e-12)
    error("sixgr:conformance:OCNGPDSCHPrecoderPowerMismatch", ...
        "OP.1 PDSCH precoder trace is %.16g, expected one.", power);
end
end

function value = localCDMGroupSize(cdm)
switch lower(strtrim(string(cdm)))
    case "nocdm"
        value = 1;
    case "fd-cdm2"
        value = 2;
    case "cdm4-fd2-td2"
        value = 4;
    otherwise
        error("sixgr:conformance:UnsupportedAcquisitionCSIRSCDM", ...
            "Unsupported acquisition CSI-RS CDM type '%s'.", cdm);
end
end

function symbols = localQPSK(stream, count)
bits = randi(stream, [0 1], 2, count);
symbols = ((1 - 2*double(bits(1,:))) + ...
    1j*(1 - 2*double(bits(2,:)))) ./ sqrt(2);
symbols = symbols(:);
end

function value = localAbsoluteSlot(carrier)
mu = log2(double(carrier.SubcarrierSpacing)/15);
if ~(isfinite(mu) && abs(mu-round(mu)) <= 1e-12)
    error("sixgr:conformance:UnsupportedNumerology", ...
        "FRC SCS %.15g kHz is not an NR power-of-two numerology.", ...
        double(carrier.SubcarrierSpacing));
end
slotsPerFrame = 10 * 2^round(mu);
value = double(carrier.NFrame) * slotsPerFrame + double(carrier.NSlot);
end

function value = localSeed(raw)
value = mod(floor(double(raw)), 2^32-1);
if value <= 0
    value = 1;
end
end
