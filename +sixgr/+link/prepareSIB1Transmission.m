function prepared=prepareSIB1Transmission(cfg,ssbInfo,varargin)
%PREPARESIB1TRANSMISSION Encode and power-bind one cell SI-only occasion.
% No SS/PBCH generation, RF/channel/noise, receiver, or UE eligibility input.
% The shared cell owner must enqueue these samples and independently commit
% original transmission evidence; preparation alone is not an emission.
assert(isstruct(cfg) && isscalar(cfg) && isstruct(ssbInfo) && isscalar(ssbInfo), ...
    'sixgr:link:InvalidSIB1Preparation','Use the frozen cell configuration and original SSB association.');
p=inputParser;
p.addParameter('AbsoluteSlot',[]);
p.parse(varargin{:});
slot=p.Results.AbsoluteSlot;
assert(isnumeric(slot) && isreal(slot) && isscalar(slot) && isfinite(slot) && ...
    slot>=0 && slot==fix(slot) && slot<flintmax/160, ...
    'sixgr:phy:broadcast:InvalidSIB1Clock','SI preparation requires an explicit absolute slot.');
assert(string(sixgr.util.structGet(ssbInfo,'WaveformDomain',''))=="physical_element_domain", ...
    'sixgr:link:SIB1PhysicalProjectionRequired', ...
    'Shared SI preparation requires the original physical-element SSB mapping, not an unapplied external map.');
tx=sixgr.phy.broadcast.generateSIB1Transmission(cfg,ssbInfo,'AbsoluteSlot',double(slot));
cfg=tx.Config;
cfg=sixgr.util.structSet(cfg,'lls6g.userContext.RuntimeSignalFamily',"SIB1");
cfg=sixgr.util.structSet(cfg,'lls6g.userContext.RuntimeCurrentDirection',"DL");
cfg=sixgr.util.structSet(cfg,'lls6g.userContext.Direction',"DL");
cfg=sixgr.util.structSet(cfg,'channel.linkDirection',"DL");
cfg=sixgr.util.structSet(cfg,'lls6g.userContext.RuntimeSlotStartTime_s', ...
    tx.WaveformStartAbsoluteSample/tx.SampleRateHz);
grid=sixgr.link.broadcastSIB1WaveformPortGrid(tx);
active=find(reshape(any(any(grid~=0,1),3),[],1)).';
assert(~isempty(active),'sixgr:link:EmptySIB1Preparation','Actual SI must contain nonzero native REs.');
txInfo=struct('OFDM',nrOFDMInfo(tx.Carrier), ...
    'PortGrid',grid(:,active,:), ...
    'PortGridAbsoluteSymbolIndices',tx.WaveformStartAbsoluteSymbolIndex0+active-1, ...
    'WaveformStartAbsoluteSymbolIndex0',tx.WaveformStartAbsoluteSymbolIndex0, ...
    'PowerNormalizationGridSource',"exact_original_sib1_physical_port_grid");
[samples,power]=sixgr.rf.applyPowerContext(tx.Waveform,cfg,'DL',txInfo,'ApplyPA',false);
txInfo.PowerContext=power;
receiver=cfg;
receiver=sixgr.util.structSet(receiver,'lls6g.runtimePowerContext',power);
stop=sixgr.phy.frame.slotStartSample(tx.Carrier,double(slot)+1,tx.SampleRateHz);
assert(tx.WaveformStartAbsoluteSample+size(samples,1)==stop && ...
    size(samples,2)==tx.SIB1SpatialMapping.NumPhysicalElements && ...
    tx.SIB1SpatialMapping.MatrixAppliedHere && ~power.PAApplied, ...
    'sixgr:link:InvalidSIB1Preparation','Retain one exact native SI slot with physical columns and deferred PA.');
runtime=tx; runtime.Waveform=samples; runtime.PowerContext=power;
prepared=struct('ExecutionStage',"sib1_waveform_prepared_not_received", ...
    'Config',cfg,'ReceiverConfig',receiver,'Tx',tx,'RuntimeTx',runtime, ...
    'Carrier',tx.Carrier,'TxInfo',txInfo,'TransmitSamples',samples,'PowerContext',power, ...
    'TransmitStartSample',tx.WaveformStartAbsoluteSample, ...
    'TransmitEndSampleExclusive',stop,'SampleRateHz',tx.SampleRateHz, ...
    'NumSamples',size(samples,1),'NumPhysicalTransmitAntennas',size(samples,2), ...
    'AbsoluteSlot',double(slot),'RuntimeSlot',double(slot)+1, ...
    'AssociatedSSBIndex',tx.AssociatedSSBIndex, ...
    'SSBEmissionIncluded',false,'RFExecutionDeferred',true, ...
    'PAExecutionDeferred',logical(power.PAExecutionDeferred),'ChannelExecutionDeferred',true);
prepared.ResourceIntervalEvidence=sixgr.truth.executedResourceIntervals(grid,double(slot));
end
