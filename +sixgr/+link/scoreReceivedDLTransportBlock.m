function [crcPass,bitErrors,bitsCompared]=scoreReceivedDLTransportBlock(decoded,reference)
% CRC is a receiver verdict. The expected payload is simulation scoring only.
assert(isstruct(decoded) && isscalar(decoded) && ...
    isfield(decoded,'CRCPass') && islogical(decoded.CRCPass) && isscalar(decoded.CRCPass) && ...
    isfield(decoded,'TransportBlock'), 'sixgr:link:DLDecodeVerdictRequired', ...
    'Scoring requires an explicit logical receiver CRC verdict and its decoded bits.');
bits=decoded.TransportBlock(:); reference=reference(:);
assert(~isempty(bits) && numel(bits)==numel(reference) && ...
    all(bits==0 | bits==1) && all(reference==0 | reference==1), ...
    'sixgr:link:DLDecodedTBSMismatch', ...
    'Decoded and reference TBs must have the same nonempty bit length; never hide an allocation mismatch by truncating.');
crcPass=decoded.CRCPass;
bitsCompared=numel(bits);
bitErrors=nnz(bits~=reference);
end
