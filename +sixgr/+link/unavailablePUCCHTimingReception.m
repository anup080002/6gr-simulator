function rx=unavailablePUCCHTimingReception(cfg,assignment,context,observation,prior,reason,threshold,thresholdSource)
% A completed physical capture whose Format-0 receiver cannot be started.
% This is NOT a detection, decoded UCI, measured DTX, or renewed timing.
assert(isa(assignment,'sixgr.phy.pucch.PUCCHReceptionAssignment') && ...
    assignment.Format==0 && assignment.ReportContextDigest==context.Digest && ...
    assignment.ConfigurationEpoch==context.ConfigurationEpoch && ...
    assignment.ReportID==context.ReportID && context.HARQACKBits>0, ...
    'sixgr:link:InvalidUnavailablePUCCHIdentity','Retain the independent HARQ receiver hypothesis.');
raw=observation.readComplete();
carrier=sixgr.phy.grid.makeCarrier(cfg); info=nrOFDMInfo(carrier);
slot0=double(assignment.Data.AbsoluteSlot0);
assert(observation.SampleRateHz==info.SampleRate && ...
    assignment.Data.RNTI==cfg.phy.pusch.RNTI, ...
    'sixgr:link:InvalidUnavailablePUCCHIdentity','Do not replace receiver identity or sample clock.');
source=""; available=NaN; sourceSlot=NaN; age=NaN; arrival=NaN;
maximum=cfg.phy.synchronization.maxReceivedULTimingAgeSlots;
if reason=="stale_received_ul_timing"
    assert(isa(prior,'sixgr.phy.sync.ReceivedULTimingReference') && isscalar(prior), ...
        'sixgr:link:InvalidUnavailablePUCCHTiming','Stale disposition requires the original measured clock.');
    % The strict align operation must have reached its freshness guard after
    % validating original identity, TAG and reception availability.
    try
        prior.alignCompletedObservation(cfg,observation,slot0);
    catch cause
        if ~strcmp(cause.identifier,'sixgr:phy:sync:StaleULTimingReference'), rethrow(cause); end
        source=prior.SourceSignal; available=prior.AvailableAtSample;
        sourceSlot=sixgr.phy.frame.slotIndexFromStartSample(carrier,prior.NominalStartSample,prior.SampleRateHz);
        age=slot0-sourceSlot; arrival=prior.ArrivalOffsetFromNominalSamples;
    end
    assert(age>maximum,'sixgr:link:InvalidUnavailablePUCCHTiming', ...
        'Do not turn a fresh or future clock into an unavailable outcome.');
else
    assert(reason=="missing_received_ul_timing" && isempty(prior), ...
        'sixgr:link:InvalidUnavailablePUCCHTiming','Only original missing/stale timing is an expected outcome.');
end
timing=struct('TimingOffsetSamples',NaN,'AppliedTimingCorrectionSamples',NaN, ...
    'TimingSource',"unavailable_"+reason,'TimingValueRole',"no_alignment_or_timing_measurement", ...
    'ReferenceSource',source,'ReferenceAvailableAtSample',available, ...
    'ReferenceSourceAbsoluteSlot0',sourceSlot,'ReferenceAgeSlots',age, ...
    'MaximumReferenceAgeSlots',double(maximum),'TargetAbsoluteSlot0',slot0, ...
    'ReferenceArrivalOffsetFromNominalSamples',arrival,'PriorClockApplied',false, ...
    'InputSampleCount',size(raw,1),'DemodulatedSampleCount',0, ...
    'OracleTimingUsed',false,'ReceiverZeroPaddingUsed',false);
emptyBits=int8(zeros(0,1));
rx=struct('ReceiverExecutionStatus',"unavailable_before_synchronization", ...
    'ReceiverUnavailableReason',reason,'FeedbackDisposition',"receiver_unavailable_"+erase(reason,"received_"), ...
    'ReceiveTiming',timing,'ReceiveFrequency',struct(), ...
    'ReceiverUsable',false,'DetectionAttempted',false,'DecodeAttempted',false, ...
    'DTX',false,'DTXDecisionAvailable',false,'DetectionOutcome',"unavailable", ...
    'DetectionMetric',NaN,'DetectionMetricValid',false, ...
    'DetectionMetricSource',"not_executed_timing_unavailable", ...
    'DetectionThreshold',threshold,'DetectionThresholdSource',thresholdSource, ...
    'ResourceExtractionAttempted',false,'ResourceExtractionAvailable',false, ...
    'DecodedSequence1',emptyBits,'DecodedSequence2',emptyBits, ...
    'DecodedFields',struct('HARQACK',emptyBits,'SR',emptyBits,'CSIPart1',emptyBits,'CSIPart2',emptyBits), ...
    'CRCPassed',false,'CRCApplicable',false,'CodeBlockCRCError',false(0,1),'UCICRCBitCount',0, ...
    'ExpectedPayloadBitCount',context.Sequence1Length+context.Sequence2Length, ...
    'WrongRNTI',false,'WrongResource',false,'WrongSequence',false, ...
    'MeasuredSINR_dB',NaN,'MeasuredSINRApplicable',false, ...
    'MeasuredSINRSource',"not_executed_timing_unavailable", ...
    'EVMPercent',NaN,'EVMApplicable',false, ...
    'FailureReason',reason,'ErrorID',"",'OraclePayloadBitsUsed',false, ...
    'AssignmentDigest',assignment.Digest,'ReportContextDigest',context.Digest, ...
    'ReceiverOnlyAssignment',true,'ReceiverAssignmentSource',string(assignment.Data.Source), ...
    'IndependentReceiverAssignment',true,'PreparedTransmitterConsumed',false, ...
    'InjectedNoiseVarianceConsumed',false,'InjectedInterferenceCovarianceConsumed',false, ...
    'GridNoiseVariance',NaN,'GridNoiseVarianceSource',"not_executed_timing_unavailable", ...
    'EffectiveGridNoiseInterferenceVariance',NaN,'DecodeNoiseInterferenceVariance',NaN, ...
    'EqualizedDecodeNoiseInterferenceVariance',NaN,'EqualizerInfo',struct(), ...
    'ChannelEstimate',[],'OFDMInfo',struct(),'ChannelEstimateApplicable',false, ...
    'NoncoherentSequenceDetection',false,'ChannelEstimationMode',"not_executed_timing_unavailable", ...
    'ReceiverObservationStartSample',observation.StartSample, ...
    'ReceiverObservationEndSampleExclusive',observation.EndSampleExclusive, ...
    'ReceiverObservationSampleRateHz',observation.SampleRateHz, ...
    'ReceiverObservationSampleSHA256',observation.sampleHash());
rx=sixgr.util.mergeStruct(rx,sixgr.phy.pucch.harqObservationEvidence(context,rx));
end
