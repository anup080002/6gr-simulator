function evidence=srsPilotPhaseEvidence(source)
% Scalar measured SRS phase evidence shared by runtime and CSV publishers.
% Compact complex receiver history is deliberately not an export column.
if nargin==0, source=struct(); end
evidence=struct('DopplerMeasurementStatus', ...
    "maximum_doppler_spread_not_identifiable_from_common_phase", ...
    'PilotCommonPhaseRate_Hz',NaN,'PilotPhaseFitResidualRMS_deg',NaN, ...
    'PilotPhasePairCount',0,'PilotPhaseMatchedChannelValueCount',0, ...
    'PilotPhaseUnaliasedHalfWidth_Hz',NaN,'PilotPhaseEvolutionSource',"", ...
    'PilotPhaseEvolutionStatus',"receiver_not_executed", ...
    'PilotPhaseObservationScope',"",'PilotPhaseHistoryStatus',"", ...
    'PilotPhasePreviousObservationTime_s',NaN,'PilotPhaseCurrentObservationTime_s',NaN, ...
    'PilotPhaseObservationSeparation_s',NaN);
for field=string(fieldnames(evidence)).'
    if isstruct(source)&&isfield(source,field) || istable(source)&&ismember(field,source.Properties.VariableNames)
        evidence.(field)=source.(field);
    end
end
end
