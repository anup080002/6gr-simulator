function [prepareOnly,received,prepared,binding] = validateDataStreamRequest(cfg,options,direction,profile,grant,phyGrant)
%VALIDATEDATASTREAMREQUEST Enforce the single frozen-grant stream boundary.
prepareOnly = logical(options.PrepareOnly);
received = ~isempty(fieldnames(options.ReceivedContext));
prepared = [];
binding = struct();
if ~(prepareOnly || received)
    return;
end
assert(~(prepareOnly && received) && string(profile)=="scheduler_truth" && ...
    options.NumFrames==1 && ~isempty(fieldnames(phyGrant)), ...
    'sixgr:link:InvalidDataStreamRequest', ...
    'Stream preparation/completion requires one frozen scheduler grant and exactly one stage.');
assert(isempty(options.InterferenceBundle), ...
    'sixgr:link:DataStreamInterferenceAlreadyComposed', ...
    'The stream owner must compose interference before providing received observations.');
binding = sixgr.link.PreparedDataTransmission.requestBinding(options,grant,phyGrant);
if received
    context = options.ReceivedContext;
    required = {'Prepared','Observation','PhysicalMeasurementObservation', ...
        'TransmitterObservation','Replay','ChannelState'};
    assert(isscalar(context) && all(isfield(context,required)) && ...
        isa(context.Prepared,'sixgr.link.PreparedDataTransmission') && isscalar(context.Prepared), ...
        'sixgr:link:IncompleteDataReceivedContext', ...
        'Completion needs retained TX plus actual transmitter, pre-RX-RF and post-RX-RF observations.');
    prepared = context.Prepared;
    prepared.assertRequest(direction,cfg,binding);
    numRx = double(phyGrant.AntennaArchitecture.NumRxAntennas);
    % Validate before any decoder, callback, table row, RNG or state update.
    prepared.readObservation(context.Observation,numRx);
    prepared.readObservation(context.PhysicalMeasurementObservation,numRx);
    prepared.readObservation(context.TransmitterObservation,prepared.NumPhysicalTransmitAntennas,"transmitter");
    assert(context.Observation.EndSampleExclusive==context.PhysicalMeasurementObservation.EndSampleExclusive, ...
        'sixgr:link:DataObservationPlaneMismatch', ...
        'Pre-front-end and post-front-end observations must cover the same received sample interval.');
    assert(isstruct(context.Replay) && isscalar(context.Replay) && ...
        isstruct(context.ChannelState) && isscalar(context.ChannelState), ...
        'sixgr:link:IncompleteDataReceivedContext','Retain actual shared-channel replay and state.');
    for name = ["ApproximationMode","RuntimeChannelReciprocityApproximationMode"]
        value = lower(strtrim(string(sixgr.util.structGet(context.Replay,name,""))));
        assert(isscalar(value) && any(value==["","none","exact"]), ...
            'sixgr:link:ProxyDataStreamForbidden', ...
            'Approximate shared-channel samples cannot be relabeled as scheduler truth.');
    end
    for name = ["FallbackUsedForPathloss","FallbackUsed","ProxyUsed","SyntheticUsed"]
        value = sixgr.util.structGet(context.Replay,name,false);
        assert((islogical(value)||isnumeric(value)) && isscalar(value) && isequal(double(value),0), ...
            'sixgr:link:ProxyDataStreamForbidden', ...
            'Fallback, proxy or synthetic shared-stream evidence is forbidden.');
    end
end
end
