function T=buildPDCCHChannelEstimateTable(rx)
%BUILDPDCCHCHANNELESTIMATETABLE Retain executed receiver candidate Hest.
% Locations come from the receiver's monitored hypothesis, never TX indices.
% Reference-port indices identify estimator dimensions, not antenna elements.
T=table();
if isempty(rx.ChannelEstimate), return; end
h=rx.ChannelEstimate;
K=size(h,1); L=size(h,2); R=size(h,3); P=size(h,4);
indices=unique([double(rx.MonitoredDataREIndices(:));double(rx.MonitoredDMRSREIndices(:))]);
assert(~isempty(indices) && all(indices>=1 & indices==fix(indices)), ...
    'sixgr:link:InvalidPDCCHChannelEvidence','Missing receiver resource coordinates.');
slotREs=K*double(rx.ReferenceGridSymbolsPerSlot);
locations=unique(mod(indices-1,slotREs));
sc=mod(locations,K); symbol=floor(locations/K);
assert(all(symbol<L),'sixgr:link:UnreceivedPDCCHChannelEvidence', ...
    'Channel evidence cannot include unreceived symbols.');
dmrsLocations=unique(mod(double(rx.MonitoredDMRSREIndices(:))-1,slotREs));
isDMRS=ismember(locations,dmrsLocations);
rows=cell(R*P,1); cursor=0;
for p=1:P
    for r=1:R
        sampleIndex=sc+1+K*symbol+K*L*(r-1)+K*L*R*(p-1);
        value=h(sampleIndex); value=value(:); n=numel(value);
        assert(all(isfinite(value)),'sixgr:link:InvalidPDCCHChannelEvidence', ...
            'Receiver channel estimates contain nonfinite values.');
        cursor=cursor+1;
        rows{cursor}=table(sc,symbol,repmat(r-1,n,1),repmat(p-1,n,1), ...
            isDMRS,real(value),imag(value),abs(value),angle(value), ...
            repmat(logical(rx.Ok),n,1),repmat(double(rx.CandidateIndex),n,1), ...
            repmat(double(rx.CandidateAggregationLevel),n,1), ...
            repmat(string(rx.ChannelEstimateSource),n,1), ...
            repmat(string(rx.ChannelEstimateMethod),n,1), ...
            repmat("actual_receiver_candidate_channel_estimate",n,1), ...
            repmat(string(rx.DCISelectionSource),n,1), ...
            'VariableNames',{'SubcarrierIndex0','SymbolIndex0','RxPortIndex0', ...
            'ReferencePortIndex0','IsDMRS','HReal','HImag','Magnitude','Phase_rad', ...
            'ReceiverAccepted','CandidateIndex','AggregationLevel', ...
            'ChannelEstimateSource','ChannelEstimateMethod','EvidenceClass','DCISelectionSource'});
    end
end
T=vertcat(rows{:});
end
