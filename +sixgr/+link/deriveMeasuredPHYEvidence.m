function value = localScalarDouble(raw)
value = NaN;
if isempty(raw)
    return;
end
try
    raw = double(raw);
catch
    return;
end
raw = raw(:);
if isempty(raw)
    return;
end
value = raw(1);
end

function value = localScalarString(raw)
value = "";
if isempty(raw)
    return;
end
try
    raw = string(raw);
catch
    return;
end
raw = raw(:);
if isempty(raw)
    return;
end
if numel(raw) == 1
    value = raw(1);
else
    value = strjoin(raw.', "|");
end
end
