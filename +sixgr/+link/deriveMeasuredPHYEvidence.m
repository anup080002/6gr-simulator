function evidence = deriveMeasuredPHYEvidence(rx)
%DERIVEMEASUREDPHYEVIDENCE Extract compact measured PHY evidence from RX output.

evidence = sixgr.link.emptyMeasuredPHYEvidenceRow();
if nargin < 1 || ~isstruct(rx) || isempty(rx)
    return;
end

numericFields = localNumericFields();
stringFields = localStringFields();

for i = 1:numel(numericFields)
    name = numericFields(i);
    if isfield(rx, name)
        evidence.(name) = localScalarDouble(rx.(name));
    end
end
for i = 1:numel(stringFields)
    name = stringFields(i);
    if isfield(rx, name)
        evidence.(name) = localScalarString(rx.(name));
    end
end

% CSI-RS physical power is carried by the receiver observation rather than
% by a top-level compatibility scalar.  Preserve both planes explicitly:
% the relative FFT-grid value is useful for DSP diagnostics, while only the
% PowerContext-calibrated value is allowed to carry dBm units.
csirs = sixgr.util.structGet(rx, "CSIRSObservation", struct());
if isstruct(csirs) && ~isempty(fieldnames(csirs))
    evidence.MeasuredCSIRSRPRelative_dB = localScalarDouble( ...
        sixgr.util.structGet(csirs, "MeasurementRelativeRSRP_dB", NaN));
    evidence.MeasuredCSIRSRP_dBm = localScalarDouble( ...
        sixgr.util.structGet(csirs, "MeasurementRSRP_dBm", NaN));
    evidence.MeasuredCSIRSRPFFTSize = localScalarDouble( ...
        sixgr.util.structGet(csirs, "MeasurementFFTSize", NaN));
    evidence.MeasuredCSIRSRPGridScaleToSqrtW = localScalarDouble( ...
        sixgr.util.structGet(csirs, "MeasurementGridScaleToSqrtW", NaN));
    evidence.MeasuredCSIRSRPSource = localScalarString( ...
        sixgr.util.structGet(csirs, "MeasurementSource", ""));
    evidence.MeasuredCSIRSRPPhysicalStatus = localScalarString( ...
        sixgr.util.structGet(csirs, "PhysicalMeasurementStatus", "not_attempted"));
    evidence.MeasuredCSIRSRPPowerReferencePlane = localScalarString( ...
        sixgr.util.structGet(csirs, "PowerReferencePlane", ""));
end
end

