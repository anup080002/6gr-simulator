function evidence = localParityEvidence(evidence, rx)
if ~isfield(rx, 'LDPCParityEvidence')
    % Compact replay rows may already carry the versioned projection. Do
    % not reinterpret them as a new receiver execution or requalify legacy
    % vectors merely because they contain finite zeros.
    if any(evidence.MeasuredLDPCParityContractVersion == ...
            ["sixgr.phy.LDPCParitySummary/v1","sixgr.phy.LDPCParitySummary/v2"])
        localValidateCompactParity(evidence, rx);
        return;
    end
    assert(strlength(evidence.MeasuredLDPCParityContractVersion)==0, ...
        'sixgr:link:InvalidLDPCParityEvidence', 'Unsupported parity projection contract.');
    defaults = sixgr.link.emptyMeasuredPHYEvidenceRow();
    names = string(fieldnames(defaults));
    names = names(startsWith(names,'MeasuredLDPCParity') & names~="MeasuredLDPCParityCheckVector");
    for index = 1:numel(names)
        evidence.(names(index)) = defaults.(names(index));
    end
    if strlength(evidence.MeasuredLDPCParityCheckVector)==0 && isfield(rx,'ParityChecks')
        raw = rx.ParityChecks;
        if isnumeric(raw) || islogical(raw)
            tokens = string(raw(:).');
            tokens(isnan(raw(:).')) = "NaN";
            tokens(raw(:).'==Inf) = "Inf";
            tokens(raw(:).'==-Inf) = "-Inf";
            evidence.MeasuredLDPCParityCheckVector = strjoin(tokens,'|');
        else
            evidence.MeasuredLDPCParityCheckVector = localScalarString(raw);
        end
    end
    evidence.MeasuredLDPCParityAvailable = 0;
    evidence.MeasuredLDPCParityScope = "unavailable_no_complete_native_parity_evidence";
    if strlength(evidence.MeasuredLDPCParityCheckVector) > 0 || ...
            ~isempty(sixgr.util.structGet(rx, 'ParityChecks', []))
        evidence.MeasuredLDPCParityScope = "legacy_unqualified_partial_or_unknown";
    end
    return;
end
original = rx.LDPCParityEvidence;
assert(isstruct(original) && isscalar(original) && ...
    all(isfield(original, {'ContractVersion','Stage','FinalParityChecksPerCodeword'})), ...
    'sixgr:link:InvalidLDPCParityEvidence', 'Complete LDPC parity evidence is malformed.');
version = localParityContract(original.ContractVersion);
if version == "sixgr.phy.LDPCParitySummary/v2"
    assert(isfield(original,'CodewordStages'), ...
        'sixgr:link:InvalidLDPCParityEvidence','V2 requires original per-codeword decoder stages.');
    stages = original.CodewordStages;
else
    assert(~isfield(original,'CodewordStages'), ...
        'sixgr:link:InvalidLDPCParityEvidence','Legacy V1 cannot acquire inferred codeword stages.');
    stages = original.Stage;
end
try
    expected = sixgr.phy.phycode.summarizeLDPCParity( ...
        original.FinalParityChecksPerCodeword,stages,version);
catch cause
    error('sixgr:link:InvalidLDPCParityEvidence', ...
        'Original parity population/stages are invalid: %s',cause.message);
end
names = fieldnames(expected);
for index = 1:numel(names)
    name = names{index};
    assert(isfield(original, name) && isequaln(original.(name), expected.(name)), ...
        'sixgr:link:InvalidLDPCParityEvidence', ...
        'LDPC parity field %s does not match the original complete matrices.', name);
end
evidence.MeasuredLDPCParityContractVersion = expected.ContractVersion;
evidence.MeasuredLDPCParityStage = expected.Stage;
evidence.MeasuredLDPCParityScope = "complete_native_final_parity_matrix_checks_by_codeblock_per_codeword";
if ~expected.Available
    evidence.MeasuredLDPCParityScope = "incomplete_codeword_population_observed_matrices_only";
end
evidence.MeasuredLDPCParityCodewordCount = numel(expected.CodewordAvailable);
evidence.MeasuredLDPCParityObservedCodewordCount = nnz(expected.CodewordAvailable);
evidence.MeasuredLDPCParityAvailable = double(expected.Available);
evidence.MeasuredLDPCParityCheckFailures = expected.UnsatisfiedCheckCount;
evidence.MeasuredLDPCParityCheckCount = expected.CheckCount;
evidence.MeasuredLDPCParityCodeBlockCount = expected.CodeBlockCount;
evidence.MeasuredLDPCParityFailedCodeBlockCount = expected.FailedCodeBlockCount;
compact = rmfield(expected, 'FinalParityChecksPerCodeword');
compact.FinalParityCheckShapesPerCodeword = cellfun(@size, ...
    expected.FinalParityChecksPerCodeword, 'UniformOutput', false);
compact.ProjectionRole = "counts_and_verdicts_not_a_second_copy_of_native_matrices";
compact.CompatibilityVectorIsCompleteEvidence = false;
compact.TransportBlockAcceptanceDetermined = false;
evidence.MeasuredLDPCParityEvidenceJSON = string(jsonencode(compact));
end

function localValidateCompactParity(evidence, rx)
% A compact replay preserves an existing producer projection, not a fresh
% matrix measurement. Require its aliases to agree with that original JSON;
% a version token alone must not qualify a legacy compatibility vector.
names = ["MeasuredLDPCParityContractVersion","MeasuredLDPCParityStage", ...
    "MeasuredLDPCParityScope","MeasuredLDPCParityEvidenceJSON", ...
    "MeasuredLDPCParityCodewordCount","MeasuredLDPCParityObservedCodewordCount", ...
    "MeasuredLDPCParityCheckCount","MeasuredLDPCParityCheckFailures", ...
    "MeasuredLDPCParityCodeBlockCount","MeasuredLDPCParityFailedCodeBlockCount", ...
    "MeasuredLDPCParityAvailable"];
assert(all(isfield(rx,cellstr(names))), 'sixgr:link:InvalidLDPCParityEvidence', ...
    'A compact parity replay must retain every original companion field.');
for name = names
    raw = rx.(name);
    assert(isequaln(raw,evidence.(name)), 'sixgr:link:InvalidLDPCParityEvidence', ...
        'Parity projection field %s must retain its original scalar type/value.',name);
end
try
    compact = jsondecode(evidence.MeasuredLDPCParityEvidenceJSON);
catch
    error('sixgr:link:InvalidLDPCParityEvidence','Parity projection JSON is malformed.');
end
assert(isstruct(compact) && isscalar(compact) && ...
    all(isfield(compact,{'ContractVersion','Stage','CodewordAvailable','Available', ...
    'CheckCount','UnsatisfiedCheckCount','CodeBlockCount','FailedCodeBlockCount', ...
    'ProjectionRole','CompatibilityVectorIsCompleteEvidence','TransportBlockAcceptanceDetermined'})), ...
    'sixgr:link:InvalidLDPCParityEvidence','Parity projection JSON is incomplete.');
version = localParityContract(compact.ContractVersion);
assert(isequal(version,evidence.MeasuredLDPCParityContractVersion) && ...
    localParityScalarText(compact.Stage)==evidence.MeasuredLDPCParityStage && ...
    localParityScalarText(compact.ProjectionRole)=="counts_and_verdicts_not_a_second_copy_of_native_matrices" && ...
    islogical(compact.CompatibilityVectorIsCompleteEvidence) && ...
    isscalar(compact.CompatibilityVectorIsCompleteEvidence) && ~compact.CompatibilityVectorIsCompleteEvidence && ...
    islogical(compact.TransportBlockAcceptanceDetermined) && ...
    isscalar(compact.TransportBlockAcceptanceDetermined) && ~compact.TransportBlockAcceptanceDetermined, ...
    'sixgr:link:InvalidLDPCParityEvidence','Parity projection contract/stage/scope is inconsistent.');
available = compact.CodewordAvailable;
assert((islogical(available) || isnumeric(available)) && ...
    isreal(available) && ~issparse(available) && ...
    (isempty(available) || isvector(available)) && all(available(:)==0 | available(:)==1), ...
    'sixgr:link:InvalidLDPCParityEvidence','Invalid codeword availability.');
if version=="sixgr.phy.LDPCParitySummary/v2"
    assert(islogical(available) || isempty(available), ...
        'sixgr:link:InvalidLDPCParityEvidence','V2 codeword availability must retain logical values.');
end
localValidateParityStages(compact,version,available);
whole = ~isempty(available) && all(available(:));
scope = "complete_native_final_parity_matrix_checks_by_codeblock_per_codeword";
if ~whole, scope = "incomplete_codeword_population_observed_matrices_only"; end
assert(islogical(compact.Available) && isscalar(compact.Available) && ...
    isequal(compact.Available,whole) && evidence.MeasuredLDPCParityAvailable==double(whole) && ...
    evidence.MeasuredLDPCParityCodewordCount==numel(available) && ...
    evidence.MeasuredLDPCParityObservedCodewordCount==nnz(available) && ...
    evidence.MeasuredLDPCParityScope==scope, ...
    'sixgr:link:InvalidLDPCParityEvidence','Parity projection population differs from its original JSON.');
sourceFields = ["CheckCount","UnsatisfiedCheckCount","CodeBlockCount","FailedCodeBlockCount"];
targetFields = ["MeasuredLDPCParityCheckCount","MeasuredLDPCParityCheckFailures", ...
    "MeasuredLDPCParityCodeBlockCount","MeasuredLDPCParityFailedCodeBlockCount"];
for index = 1:numel(sourceFields)
    raw = compact.(sourceFields(index));
    if isempty(raw), raw = NaN; end % JSON null is the unavailable total.
    assert(isnumeric(raw) && isreal(raw) && isscalar(raw) && ...
        isequaln(raw,evidence.(targetFields(index))) && ...
        ((whole && isfinite(raw) && raw>=0 && raw==fix(raw)) || (~whole && isnan(raw))), ...
        'sixgr:link:InvalidLDPCParityEvidence','Parity projection aggregate changed or is malformed.');
end
end

function version = localParityContract(raw)
version = localParityScalarText(raw);
assert(any(version==["sixgr.phy.LDPCParitySummary/v1","sixgr.phy.LDPCParitySummary/v2"]), ...
    'sixgr:link:InvalidLDPCParityEvidence','Unsupported parity evidence contract.');
end

function value = localParityScalarText(raw)
assert((ischar(raw) && (isrow(raw) || isempty(raw))) || ...
    (isstring(raw) && isscalar(raw)), ...
    'sixgr:link:InvalidLDPCParityEvidence','Parity identity must retain scalar text.');
value = string(raw);
assert(isscalar(value) && ~ismissing(value), ...
    'sixgr:link:InvalidLDPCParityEvidence','Parity identity cannot be missing.');
end

function localValidateParityStages(compact,version,available)
id = 'sixgr:link:InvalidLDPCParityEvidence';
stage = localParityScalarText(compact.Stage);
allowed = ["initial_decode","harq_combined_decode"];
if version=="sixgr.phy.LDPCParitySummary/v1"
    assert(any(stage==allowed) && ~isfield(compact,'CodewordStages'),id, ...
        'Legacy V1 preserves its original aggregate stage without per-codeword reconstruction.');
    return;
end
assert(isfield(compact,'CodewordStages'),id,'V2 requires ordered codeword stages.');
raw = compact.CodewordStages;
% JSON arrays become column cellstr; singleton arrays can become char, and
% an empty array becomes numeric []. Normalize only these serialization
% shapes, never a numeric/code-point decoder-stage value.
if isempty(available)
    assert(isempty(raw),id,'Empty parity populations cannot contain stages.');
    stages = strings(1,0);
elseif iscell(raw)
    assert(isvector(raw) && numel(raw)==numel(available),id,'Codeword stage count differs.');
    stages = strings(1,numel(raw));
    for index=1:numel(raw), stages(index)=localParityScalarText(raw{index}); end
elseif isstring(raw) && isvector(raw)
    assert(~any(ismissing(raw)),id,'Codeword stages cannot be missing.');
    stages = reshape(raw,1,[]);
else
    stages = localParityScalarText(raw);
end
assert(numel(stages)==numel(available),id,'Codeword stage count differs.');
observed = reshape(logical(available),1,[]);
assert(all(ismember(stages(observed),allowed)) && all(stages(~observed)==""),id, ...
    'Only observed codewords may carry an initial/combined decoder stage.');
actual = stages(observed);
if isempty(actual), expected="";
elseif all(actual==actual(1)), expected=actual(1);
else, expected="mixed_codeword_decode"; end
assert(stage==expected,id,'Aggregate parity stage disagrees with original codeword stages.');
end

function value = localScalarDouble(raw)
value = NaN;
if isempty(raw)
    return;
end
try
    raw = double(raw);
catch
    return;
end
raw = raw(:);
if isempty(raw)
    return;
end
value = raw(1);
end

function value = localScalarString(raw)
value = "";
if isempty(raw)
    return;
end
try
    raw = string(raw);
catch
    return;
end
raw = raw(:);
if isempty(raw)
    return;
end
if numel(raw) == 1
    value = raw(1);
else
    value = strjoin(raw.', "|");
end
end
