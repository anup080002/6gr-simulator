function [outcome,state]=finalizeDLSCHCodewordOutcomes(decode,cfg,varargin)
%FINALIZEDLSCHCODEWORDOUTCOMES Select actual final decoder results per CW.
% This boundary does not decide a MAC delivery or fabricate a transport-block
% identity. Receiver-owned decoding is already final and is never repeated.
% The legacy outer-HARQ mode may decode a failed current CW once after its
% explicitly indexed prior is combined. Bits/LLRs remain in STATE, not in the
% compact OUTCOME. The throughput owner must separately bind its completed
% observation; this helper alone does not qualify a published trial.
ip=inputParser;
ip.addParameter('Mode',"receiver_owned_final",@(x)ischar(x)||(isstring(x)&&isscalar(x)));
ip.addParameter('PriorRecoveredLLR',[],@(x)isempty(x)||isnumeric(x)||isstruct(x)||iscell(x));
ip.parse(varargin{:}); opt=ip.Results;
mode=string(opt.Mode);
assert(any(mode==["receiver_owned_final","legacy_outer_harq"]), ...
    'sixgr:link:DLSCHFinalMode','An explicit supported final decoder mode is required.');
[words,n]=localWords(decode);
prior=localPriorCells(opt.PriorRecoveredLLR,n);
hasPrior=cellfun(@localHasPrior,prior);
assert(mode=="legacy_outer_harq" || ~any(hasPrior), ...
    'sixgr:link:DLSCHFinalDuplicateCombining', ...
    'Receiver-owned final decoding cannot accept a second external prior.');
receipts=cell(1,n); bits=cell(1,n); combined=cell(1,n);
buffers=cell(1,n); combines=cell(1,n); currentBits=cell(1,n);
currentCRC=false(1,n); finalCRC=false(1,n); iterations=nan(1,n);
extraDecodes=zeros(1,n);
originalParity=cell(1,n); selectedParity=cell(1,n); selectedPolicy=cell(1,n);
for cw=1:n
    d=words{cw}; localValidateWord(d,cw-1);
    initialInfo=d.HARQCombineInfo;
    assert(~(mode=="legacy_outer_harq" && logical(initialInfo.Applied) && hasPrior(cw)), ...
        'sixgr:link:DLSCHFinalDuplicateCombining', ...
        'Already-combined canonical soft evidence cannot be combined with the same outer prior again.');
    currentBits{cw}=int8(d.TransportBlock(:)); bits{cw}=currentBits{cw};
    currentCRC(cw)=logical(d.CRCPass); finalCRC(cw)=currentCRC(cw);
    combined{cw}=d.HARQCombinedLLR; combines{cw}=initialInfo;
    buffers{cw}=initialInfo.SoftBuffer;
    iterations(cw)=mean(double(d.ActiveIterations(:)),'omitnan');
    diagnostic=localOriginalDiagnostics(d);
    originalParity{cw}=sixgr.util.structGet(d,'LDPCParityEvidence',[]);
    selected="original_canonical_decoder_result";
    selectedDomain="canonical_decoder_mother_code";
    selectedCombining=logical(initialInfo.Applied);
    if mode=="legacy_outer_harq" && hasPrior(cw)
        % Pass the selected prior, but retain the original one-based CW
        % index: equal mother-code shapes/hashes are not codeword identity.
        [combined{cw},combines{cw}]=sixgr.phy.harq.combineSoftLLR( ...
            d.RateRecoveredLLR,prior{cw},'CurrentLayout',d.CodingLayout, ...
            'CodewordIndex',cw,'HARQKey',initialInfo.HARQKey);
        buffers{cw}=combines{cw}.SoftBuffer;
        if ~currentCRC(cw) && combines{cw}.Applied
            [verdict,it,decodedBits,diagnostic]=sixgr.phy.harq.decodeCombinedDLSCH( ...
                d.CodingLayout,combined{cw},cfg);
            assert(islogical(verdict) && isscalar(verdict) && ...
                isequal(verdict,diagnostic.CRCPass) && ...
                diagnostic.TransportBlockSize==double(d.CodingPlan.TransportBlockSize) && ...
                diagnostic.DecodedTransportBlockLength==numel(decodedBits), ...
                'sixgr:link:DLSCHFinalDecodeMismatch', ...
                'The selected combined result must retain its actual primitive verdict and length.');
            bits{cw}=int8(decodedBits(:)); finalCRC(cw)=verdict;
            iterations(cw)=it; extraDecodes(cw)=1;
            selected="outer_decodeCombinedDLSCH_result";
            selectedDomain="outer_prior_plus_current_mother_code";
            selectedCombining=true;
        end
    end
    selectedParity{cw}=sixgr.util.structGet(diagnostic,'LDPCParityEvidence',[]);
    selectedPolicy{cw}=sixgr.util.structGet(diagnostic,'LDPCPolicyReceipt',struct());
    parityProjection=localParityProjection(selectedParity{cw});
    p=d.CodingPlan; h=combines{cw};
    receipts{cw}=struct('ContractVersion',"DLSCHFinalCodewordDecision/v1", ...
        'CodewordIndex',cw-1,'CodewordIndexBase',0,'NumCodewords',n, ...
        'CodingPlanID',string(d.CodingPlanID), ...
        'CodingLayoutHash',string(d.CodingLayout.CodingLayoutHash), ...
        'CombineSignature',string(d.CodingLayout.CombineSignature), ...
        'RateMatchSignature',string(d.CodingLayout.RateMatchSignature), ...
        'TransportBlockSize',double(p.TransportBlockSize),'RV',double(p.RV), ...
        'Modulation',string(p.Modulation),'TargetCodeRate',double(p.TargetCodeRate), ...
        'CodewordLayerCount',double(p.NumLayers), ...
        'OriginalDecoderSource',string(d.Source), ...
        'OriginalDecoderCRCPass',currentCRC(cw), ...
        'CurrentAttemptStandaloneCRCMeasured',~logical(initialInfo.Applied), ...
        'SelectedDecoderSource',selected,'DecoderCRCInputDomain',selectedDomain, ...
        'SelectedDecoderUsedCombining',selectedCombining, ...
        'AdditionalDecoderInvocationCount',extraDecodes(cw), ...
        'CRCPass',finalCRC(cw),'CRCError',~finalCRC(cw), ...
        'TransportBlockCRCPass',logical(diagnostic.TransportBlockCRCPass), ...
        'TransportBlockCRCError',logical(diagnostic.TransportBlockCRCError), ...
        'TransportBlockLengthMatch',logical(diagnostic.TransportBlockLengthMatch), ...
        'DecodedTransportBlockLength',double(diagnostic.DecodedTransportBlockLength), ...
        'DecodedTransportBlockSHA256',string(sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(bits{cw})), ...
        'DecodedTransportBlockHashSerialization',"WaveformHash.runtimeArray_class_dimensions_real_imag_double", ...
        'SuccessfulDecodedBits',double(p.TransportBlockSize)*double(finalCRC(cw)), ...
        'CodeBlockCRCApplicable',double(p.NumCodeBlocks)>1, ...
        'CodeBlockCRCError',diagnostic.CodeBlockCRCError, ...
        'CodeBlockCRCPass',diagnostic.CodeBlockCRCPass, ...
        'AcceptanceBasis',string(diagnostic.AcceptanceBasis), ...
        'DecoderIterations',iterations(cw), ...
        'LDPCPolicyReceipt',selectedPolicy{cw}, ...
        'LDPCParityAvailable',parityProjection.MeasuredLDPCParityAvailable, ...
        'LDPCParityStage',parityProjection.MeasuredLDPCParityStage, ...
        'LDPCParityEvidenceJSON',parityProjection.MeasuredLDPCParityEvidenceJSON, ...
        'RetainedSoftBufferCombiningApplied',logical(h.Applied), ...
        'RetainedSoftBufferResetPrior',logical(h.ResetPrior), ...
        'HARQCodewordIndexBase',1, ...
        'OriginalHARQCombineInfo',localCompact(initialInfo), ...
        'RetainedHARQCombineInfo',localCompact(h), ...
        'UniqueTransportBlockIdentityAvailable',false);
end
offeredBits=cellfun(@(r)r.TransportBlockSize,receipts);
outcome=struct('ContractVersion',"DLSCHFinalDecoderOutcome/v1", ...
    'Stage',"final_decoder_selection_before_completed_trial_binding", ...
    'PopulationScope',"one_decoder_attempt_per_explicit_codeword", ...
    'Mode',mode,'NumCodewords',n,'CodewordIndexBase',0, ...
    'Codewords',{receipts},'CRCPassPerCodeword',finalCRC, ...
    'CRCErrorPerCodeword',~finalCRC,'CRCPass',all(finalCRC), ...
    'CRCError',any(~finalCRC), ...
    'OfferedBitsPerCodeword',offeredBits, ...
    'SuccessfulDecodedBitsPerCodeword',offeredBits.*double(finalCRC), ...
    'SuccessfulDecodedBits',sum(offeredBits.*double(finalCRC)), ...
    'DecodedBitsScope',"this_decoder_attempt_not_unique_MAC_delivery", ...
    'AdditionalDecoderInvocationCount',sum(extraDecodes), ...
    'FinalThroughputOutcomeBound',false, ...
    'UniqueTransportBlockIdentityAvailable',false, ...
    'StatisticalIndependenceClaimed',false);
state=struct('TransportBlocks',{bits},'OriginalTransportBlocks',{currentBits}, ...
    'CombinedLLRPerCodeword',{combined},'SoftBufferPerCodeword',{buffers}, ...
    'HARQCombineInfoPerCodeword',{combines}, ...
    'OriginalDecoderCRCPassPerCodeword',currentCRC, ...
    'OriginalLDPCParityEvidencePerCodeword',{originalParity}, ...
    'LDPCParityEvidencePerCodeword',{selectedParity}, ...
    'LDPCPolicyReceiptPerCodeword',{selectedPolicy}, ...
    'DecoderIterationsPerCodeword',iterations);
end

function [words,n]=localWords(d)
assert(isstruct(d)&&isscalar(d)&&isfield(d,'ContractVersion'), ...
    'sixgr:link:DLSCHFinalDecodeRequired','An original canonical decoder result is required.');
if string(d.ContractVersion)=="ExplicitDLSCHDecodeCodeword/v1"
    words={d}; n=1;
else
    assert(string(d.ContractVersion)=="ExplicitDLSCHDecode/v1" && ...
        isfield(d,'NumCodewords') && isequal(double(d.NumCodewords),2) && ...
        isfield(d,'Codewords') && iscell(d.Codewords) && numel(d.Codewords)==2, ...
        'sixgr:link:DLSCHFinalDecodeRequired','Two-CW results require exactly two original decoder entries.');
    words=reshape(d.Codewords,1,[]); n=2;
end
end

function localValidateWord(d,index)
fields={'ContractVersion','CodewordIndex','CodingPlan','CodingPlanID','CodingLayout', ...
    'RateRecoveredLLR','HARQCombinedLLR','HARQCombineInfo','TransportBlock', ...
    'CRCPass','CRCError','TransportBlockCRCPass','TransportBlockCRCError', ...
    'TransportBlockLengthMatch','CodeBlockCRCError','CodeBlockCRCPass', ...
    'ActiveIterations','AcceptanceBasis','Source'};
id='sixgr:link:DLSCHFinalCodewordMismatch';
assert(isstruct(d)&&isscalar(d)&&all(isfield(d,fields)),id, ...
    'Each codeword must retain its original decoder evidence.');
p=d.CodingPlan; l=d.CodingLayout; h=d.HARQCombineInfo;
assert(string(d.ContractVersion)=="ExplicitDLSCHDecodeCodeword/v1" && ...
    isscalar(d.CodewordIndex) && double(d.CodewordIndex)==index && ...
    isstruct(p)&&isscalar(p)&&isstruct(l)&&isscalar(l)&&isstruct(h)&&isscalar(h) && ...
    all(isfield(p,{'CodewordIndex','PlanID','CodingLayoutHash','CombineSignature','RateMatchSignature', ...
        'TransportBlockSize','MotherCodeLength','NumCodeBlocks','RV','Modulation','TargetCodeRate','NumLayers'})) && ...
    all(isfield(l,{'CodewordIndex','PlanID','CodingLayoutHash','CombineSignature','RateMatchSignature'})) && ...
    all(isfield(h,{'CodewordIndex','Applied','ResetPrior','SoftBuffer','HARQKey'})),id, ...
    'Final decisions require explicit codeword/plan/layout/HARQ identities.');
assert(isscalar(p.CodewordIndex) && isscalar(l.CodewordIndex) && isscalar(h.CodewordIndex) && ...
    islogical(h.Applied) && isscalar(h.Applied) && islogical(h.ResetPrior) && isscalar(h.ResetPrior) && ...
    double(p.CodewordIndex)==index && double(l.CodewordIndex)==index && ...
    double(h.CodewordIndex)==index+1 && string(d.CodingPlanID)==string(p.PlanID) && ...
    string(l.PlanID)==string(p.PlanID),id,'Original codeword and coding-plan identities disagree.');
for name=["CodingLayoutHash","CombineSignature","RateMatchSignature"]
    assert(isscalar(string(p.(name))) && strlength(string(p.(name)))>0 && ...
        isequal(string(p.(name)),string(l.(name))),id,'Original layout identity differs from its plan.');
end
assert(isequal(size(d.RateRecoveredLLR),[double(p.MotherCodeLength) double(p.NumCodeBlocks)]) && ...
    isequal(size(d.HARQCombinedLLR),size(d.RateRecoveredLLR)) && ...
    numel(d.TransportBlock)==double(p.TransportBlockSize) && ...
    all(d.TransportBlock(:)==0|d.TransportBlock(:)==1),id, ...
    'Original soft-domain and transport-block lengths must match the retained plan.');
for name=["CRCPass","CRCError","TransportBlockCRCPass","TransportBlockCRCError","TransportBlockLengthMatch"]
    assert(islogical(d.(name)) && isscalar(d.(name)),id,'Original CRC/length flags must be logical scalars.');
end
assert(d.TransportBlockLengthMatch && d.CRCPass==d.TransportBlockCRCPass && ...
    d.CRCError==~d.CRCPass && d.TransportBlockCRCError==~d.TransportBlockCRCPass && ...
    isequaln(d.CodeBlockCRCPass,~logical(d.CodeBlockCRCError)),id, ...
    'Transport acceptance and separate CB diagnostics must retain the original receiver verdict.');
end

function cells=localPriorCells(prior,n)
if ~localHasPrior(prior), cells=cell(1,n); return; end
if iscell(prior)
    assert(numel(prior)==n,'sixgr:link:DLSCHFinalPriorCodewordCount', ...
        'Outer HARQ requires one explicitly ordered prior entry per codeword.');
    cells=reshape(prior,1,[]);
elseif n==1
    cells={prior};
else
    error('sixgr:link:DLSCHFinalPriorCodewordCount', ...
        'A scalar/aggregate prior cannot stand in for two indexed outer-HARQ buffers.');
end
if n>1
    for cw=1:n
        v=cells{cw}; if ~localHasPrior(v), continue; end
        if isstruct(v)&&isscalar(v)&&isfield(v,'SoftBuffer'), v=v.SoftBuffer; end
        assert(isstruct(v)&&isscalar(v)&&all(isfield(v,{'CodewordIndex','LLRSum','ObservationWeight'})) && ...
            isnumeric(v.CodewordIndex)&&isscalar(v.CodewordIndex)&&v.CodewordIndex==cw, ...
            'sixgr:phy:harq:SoftBufferCodewordMismatch', ...
            'Each two-codeword prior must preserve its original one-based buffer identity.');
    end
end
end

function tf=localHasPrior(v)
tf=~isempty(v);
if isstruct(v), tf=~isempty(fieldnames(v));
elseif iscell(v), tf=any(cellfun(@localHasPrior,v)); end
end

function d=localOriginalDiagnostics(word)
d=struct('TransportBlockSize',double(word.CodingPlan.TransportBlockSize), ...
    'DecodedTransportBlockLength',numel(word.TransportBlock), ...
    'TransportBlockLengthMatch',word.TransportBlockLengthMatch, ...
    'TransportBlockCRCPass',word.TransportBlockCRCPass, ...
    'TransportBlockCRCError',word.TransportBlockCRCError, ...
    'CodeBlockCRCError',word.CodeBlockCRCError,'CodeBlockCRCPass',word.CodeBlockCRCPass, ...
    'CRCPass',word.CRCPass,'AcceptanceBasis',word.AcceptanceBasis);
% Legacy retained decoder objects may predate the additive diagnostics. Do
% not backfill them from present configuration or pretend a new decode ran.
for name=["LDPCParityEvidence","LDPCPolicyReceipt"]
    if isfield(word,name), d.(name)=word.(name); end
end
end

function projection=localParityProjection(parity)
rx=struct();
if ~isempty(parity), rx.LDPCParityEvidence=parity; end
projection=sixgr.link.deriveMeasuredPHYEvidence(rx);
end

function compact=localCompact(info)
compact=rmfield(info,'SoftBuffer');
end
