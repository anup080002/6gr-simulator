function grid = broadcastSIB1WaveformPortGrid(tx, logicalGrid)
%BROADCASTSIB1WAVEFORMPORTGRID Retained SI grid in the emitted sample domain.
% External physical projection is not an executed antenna map. In that
% domain preserve the actual logical-port grid, never apply the retained
% physical beam solely to make a power or resource export look physical.
arguments
    tx (1,1) struct
    logicalGrid {mustBeNumeric} = tx.SIB1Grid
end
mapping = sixgr.util.structGet(tx, "SIB1SpatialMapping", struct());
required = {'WaveformDomain','MatrixAppliedHere','PhysicalProjectionOwner', ...
    'PrecoderMatrix','NumLogicalPorts','NumPhysicalElements','NumWaveformColumns'};
assert(all(isfield(mapping, required)), ...
    'sixgr:link:MissingBroadcastSIB1PortGrid', ...
    'SIB1 requires its retained producer grid and spatial-domain evidence.');
domain = string(mapping.WaveformDomain);
applied = mapping.MatrixAppliedHere;
row = mapping.PrecoderMatrix;
nPorts = size(tx.Waveform, 2);
assert(isscalar(domain) && islogical(applied) && isscalar(applied) && ...
    isnumeric(row) && isrow(row) && all(isfinite(row)) && any(row~=0) && ...
    mapping.NumLogicalPorts==1 && mapping.NumPhysicalElements==numel(row) && ...
    mapping.NumWaveformColumns==nPorts && size(tx.SIB1Waveform,2)==nPorts && ...
    ~isempty(logicalGrid) && size(logicalGrid,1)==12*tx.Carrier.NSizeGrid && ...
    size(logicalGrid,3)==1 && ndims(logicalGrid)<=3 && all(isfinite(logicalGrid),'all') && ...
    string(tx.SSBInfo.WaveformDomain)==domain, ...
    'sixgr:link:MissingBroadcastSIB1PortGrid', ...
    'Retained SI grid, SSB domain and emitted waveform ports must agree.');
switch domain
    case "physical_element_domain"
        assert(applied && nPorts==numel(row) && ...
            string(mapping.PhysicalProjectionOwner)=="sib1_waveform_composer", ...
            'sixgr:link:MissingBroadcastSIB1PortGrid', ...
            'Physical SI grid requires the matrix actually applied by its waveform producer.');
        grid = reshape(logicalGrid(:)*cast(row,'like',logicalGrid), ...
            size(logicalGrid,1),size(logicalGrid,2),nPorts);
    case "logical_rf_chain_post_analog_precoder"
        assert(~applied && nPorts==1 && ...
            string(mapping.PhysicalProjectionOwner)=="external_physical_projection_required", ...
            'sixgr:link:MissingBroadcastSIB1PortGrid', ...
            'Externally projected SI must retain its one emitted logical port, not claim element samples.');
        grid = logicalGrid;
    otherwise
        error('sixgr:link:MissingBroadcastSIB1PortGrid', ...
            'Unsupported retained SIB1 waveform domain: %s.', domain);
end
end
