function evidence=modulationDiagnosticsExport(metrics)
% Named diagnostics retain operands; none is independent interference truth.
if nargin==0
    metrics=sixgr.link.deriveModulationTrackingMetrics(struct(),struct(),struct(),"DL");
end
names=["DecisionResidualSymbolPower_dB","DecisionResidualEnergy", ...
    "DecisionReferenceEnergy","DecisionResidualSampleCount","DecisionResidualRatio_dB", ...
    "ResidualMetricDefinition","HestCoarseReconstructionErrorRatio_dB", ...
    "HestCoarseReconstructionErrorEnergy","HestCoarseReconstructionReferenceEnergy", ...
    "HestMagnitudeStd_dB","HestDiagnosticSampleCount","HestDiagnosticDefinition", ...
    "HestMagnitudeDefinition","ChannelAgingDiagnosticDefinition"];
evidence=struct(); for name=names, evidence.(name)=metrics.(name); end
resourceNames=string(fieldnames(sixgr.phy.resource.summarizeResourceSets())).';
for name=resourceNames, evidence.(name)=metrics.(name); end
end
