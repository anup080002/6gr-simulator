function row=scoreIsolatedDataChannelEstimate(rx,wave,cfg,direction,context)
% Post-decode scoring of actual pilot Hest against retained noiseless IQ.
% No reference is passed to a receiver or used to select a grant/feedback.
if direction=="DL"
    snapshot=sixgr.phy.dl.capturePDSCHChannelEstimate(rx);
    channel="PDSCH";
else
    assert(direction=="UL",'sixgr:link:ChannelScoringDirection','Use an explicit DL or UL direction.');
    snapshot=sixgr.phy.ul.capturePUSCHChannelEstimate(rx);
    channel="PUSCH";
end
hash=string(sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(wave));
execution=struct('Contract',"isolated_executed_data_scoring/v1", ...
    'Direction',direction,'ReceiveStartSample',0, ...
    'SampleRateHz',snapshot.ReceiverChannelOperator.SampleRateHz,'InputConfig',cfg);
capture=struct('Source',"isolated_same_executed_desired_link_pre_noise_interference_rx_RF", ...
    'WaveformSHA256',hash,'ReceiverEstimatorInput',false, ...
    'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0);
[reference,evidence]=sixgr.truth.sharedDataScoringWaveformReference(snapshot,execution,wave,capture);
context.Channel=channel;
context.ChannelEstimateSource=snapshot.Source;
context.ChannelReferenceSource=evidence.Source;
context.ChannelReferencePlane=evidence.ReferencePlane;
[resources,score]=sixgr.report.buildReceiverChannelEstimateTable( ...
    snapshot,reference,snapshot.PilotIndices,context);
row=struct('NMSE_dB',score.dB,'NMSESource',evidence.Source, ...
    'ChannelEstimateCaptureStatus',"measured_and_independently_scored_after_reception", ...
    'ChannelEstimateReferencePlane',evidence.ReferencePlane, ...
    'ChannelEstimateReferenceUsedByReceiver',false, ...
    'ChannelEstimateReferenceRFImpairmentsIncluded',evidence.RFImpairmentsIncluded, ...
    'ChannelEstimateComparedValues',score.ComparedComplexValueCount, ...
    'ChannelEstimateErrorEnergy',score.ErrorEnergy, ...
    'ChannelEstimateReferenceEnergy',score.ReferenceEnergy, ...
    'ChannelEstimateResourcesCSV',"",'ChannelEstimateResourcesCSVSHA256',"", ...
    'ChannelEstimateMATFile',"",'ChannelEstimateMATFileSHA256',"");
root=string(sixgr.util.structGet(cfg,'run.rootRunFolder',""));
if strlength(root)==0, return; end
assert(isfolder(root),'sixgr:link:ChannelScoringRoot','Use the configured existing run folder.');
identity=string(sixgr.phy.waveform.WaveformHash.bytes( ...
    jsonencode(context)+"|"+hash+"|"+string(sixgr.channel.ChannelFactory.runtimeNumericArraySHA256( ...
    [resources.HReal resources.HImag]))));
stem=lower(channel)+"_isolated_"+identity;
csvRelative=fullfile('channel_estimation','csv',stem+".csv");
matRelative=fullfile('channel_estimation','mat',stem+".mat");
csvPath=fullfile(root,csvRelative); matPath=fullfile(root,matRelative);
% Content-addressed repeated publication may reuse only identical evidence.
if ~isfile(csvPath)
    sixgr.util.csvWriteTable(csvPath,resources,'PreserveSchema',true,'RoundTripNumericText',true);
end
saved=sixgr.util.csvReadTable(csvPath,'TextType','string');
assert(height(saved)==score.ComparedComplexValueCount && ...
    isequaln(saved.HReal,resources.HReal) && isequaln(saved.HImag,resources.HImag) && ...
    isequaln(saved.ReferenceHReal,resources.ReferenceHReal) && ...
    isequaln(saved.ReferenceHImag,resources.ReferenceHImag), ...
    'sixgr:link:ChannelScoringCSVClosure','Published complex values must match the scored receiver resources.');
if ~isfile(matPath)
    sixgr.util.matSave(matPath,struct('Snapshot',snapshot,'ReferenceEvidence',evidence, ...
        'Resources',resources,'Score',score,'DesiredWaveformSHA256',hash), ...
        'UseArtifactStore',false);
end
row.ChannelEstimateResourcesCSV=string(csvRelative);
row.ChannelEstimateResourcesCSVSHA256=string(sixgr.phy.waveform.WaveformHash.file(csvPath));
row.ChannelEstimateMATFile=string(matRelative);
row.ChannelEstimateMATFileSHA256=string(sixgr.phy.waveform.WaveformHash.file(matPath));
end
