function row=scoreIsolatedDataChannelEstimate(rx,wave,cfg,direction,context,replay)
% Post-decode scoring of actual pilot Hest against retained noiseless IQ.
% No reference is passed to a receiver or used to select a grant/feedback.
if direction=="DL"
    snapshot=sixgr.phy.dl.capturePDSCHChannelEstimate(rx);
    channel="PDSCH";
else
    assert(direction=="UL",'sixgr:link:ChannelScoringDirection','Use an explicit DL or UL direction.');
    snapshot=sixgr.phy.ul.capturePUSCHChannelEstimate(rx);
    channel="PUSCH";
end
hash=string(sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(wave));
execution=struct('Contract',"isolated_executed_data_scoring/v1", ...
    'Direction',direction,'ReceiveStartSample',0, ...
    'SampleRateHz',snapshot.ReceiverChannelOperator.SampleRateHz,'InputConfig',cfg);
capture=struct('Source',"isolated_same_executed_desired_link_pre_noise_interference_rx_RF", ...
    'WaveformSHA256',hash,'ReceiverEstimatorInput',false, ...
    'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0);
% Post-decode scoring alone can use the executed RX clock transformation.
% This is not a timing estimate, and is never supplied to the receiver.
assert(isfield(replay,'TimingOffsetApplied') && isscalar(replay.TimingOffsetApplied), ...
    'sixgr:link:MissingDataScoringTimingReplay','Retain the executed RX timing operation.');
delay=0;
if logical(replay.TimingOffsetApplied)
    delay=double(replay.InjectedTimingOffset_samples);
    validateattributes(delay,{'numeric'},{'scalar','real','finite'});
end
capture.RecordedReceiverTimingOffset_samples=delay;
for name=["CFOApplied","InjectedCFO_Hz","RFEndpoint","RFStageOrder"]
    assert(isfield(replay,name),'sixgr:link:MissingDataScoringFrequencyReplay', ...
        'Retain actual RX frequency execution, not the configured or estimated CFO.');
    capture.ReceiverClockExecution.(name)=replay.(name);
end
[reference,evidence,unmatchedReference,unmatchedEvidence]= ...
    sixgr.truth.sharedDataScoringWaveformReference(snapshot,execution,wave,capture);
context.Channel=channel;
context.ChannelEstimateSource=snapshot.Source;
context.ChannelReferenceSource=evidence.Source;
context.ChannelReferencePlane=evidence.ReferencePlane;
[resources,score]=sixgr.report.buildReceiverChannelEstimateTable( ...
    snapshot,reference,snapshot.PilotIndices,context);
unmatchedContext=context; unmatchedContext.ChannelReferencePlane=unmatchedEvidence.ReferencePlane;
[unmatched,unmatchedScore]=sixgr.report.buildReceiverChannelEstimateTable( ...
    snapshot,unmatchedReference,snapshot.PilotIndices,unmatchedContext);
resources.FrequencyUnmatchedReferenceHReal=unmatched.ReferenceHReal;
resources.FrequencyUnmatchedReferenceHImag=unmatched.ReferenceHImag;
resources.FrequencyUnmatchedErrorEnergy=unmatched.ChannelErrorEnergy;
resources.FrequencyUnmatchedReferenceEnergy=unmatched.ReferenceChannelEnergy;
resources.FrequencyUnmatchedComparisonRole=repmat(unmatchedEvidence.ComparisonRole,height(resources),1);
% Identical corrected pilot values do not imply identical capture clocks.
% Bind the archive to the actual receiver operations and scoring replay too;
% neither operation is inferred from configured impairments here. Hash the
% complex combiner losslessly rather than passing it through JSON encoding.
operator=snapshot.ReceiverChannelOperator;
operator.ReceiveCombiningMatrixSHA256=string( ...
    sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(operator.ReceiveCombiningMatrix));
operator=rmfield(operator,'ReceiveCombiningMatrix');
operator.RecordedReceiverTimingOffset_samples=delay;
operator.ExecutedReceiverCFO_Hz=evidence.ExecutedReceiverCFO_Hz;
identity=string(sixgr.phy.waveform.WaveformHash.bytes( ...
    "isolated_channel_estimate/v4|"+jsonencode(context)+"|"+hash+"|"+ ...
    jsonencode(operator)+"|"+ ...
    string(sixgr.channel.ChannelFactory.runtimeNumericArraySHA256( ...
    [resources.SubcarrierIndex0 resources.SymbolIndex0 resources.RxBranchIndex0 ...
     resources.ReferencePortIndex0 resources.HReal resources.HImag ...
     resources.ReferenceHReal resources.ReferenceHImag]))));
observation="isolated_hest_"+identity;
resources.ChannelEstimateObservationID=repmat(observation,height(resources),1);
row=struct('NMSE_dB',score.dB,'NMSESource',evidence.Source, ...
    'NMSEFrequencyUnmatchedDiagnostic_dB',unmatchedScore.dB, ...
    'ChannelEstimateExecutedReceiverCFO_Hz',evidence.ExecutedReceiverCFO_Hz, ...
    'ChannelEstimateObservationID',observation, ...
    'ChannelEstimateCaptureStatus',"measured_and_independently_scored_after_reception", ...
    'ChannelEstimateReferencePlane',evidence.ReferencePlane, ...
    'ChannelEstimateReferenceUsedByReceiver',false, ...
    'ChannelEstimateReferenceRFImpairmentsIncluded',evidence.RFImpairmentsIncluded, ...
    'ChannelEstimateComparedValues',score.ComparedComplexValueCount, ...
    'ChannelEstimateErrorEnergy',score.ErrorEnergy, ...
    'ChannelEstimateReferenceEnergy',score.ReferenceEnergy, ...
    'ChannelEstimateResourcesCSV',"",'ChannelEstimateResourcesCSVSHA256',"", ...
    'ChannelEstimateMATFile',"",'ChannelEstimateMATFileSHA256',"");
for field=string(fieldnames(score)).'
    if startsWith(field,"ChannelSGCS"), row.(field)=score.(field); end
end
row.ChannelSGCSReferencePlane=evidence.ReferencePlane;
row.ChannelSGCSReferenceSource=evidence.Source;
root=string(sixgr.util.structGet(cfg,'run.rootRunFolder',""));
if strlength(root)==0, return; end
assert(isfolder(root),'sixgr:link:ChannelScoringRoot','Use the configured existing run folder.');
stem=lower(channel)+"_isolated_"+identity;
csvRelative=fullfile('channel_estimation','csv',stem+".csv");
matRelative=fullfile('channel_estimation','mat',stem+".mat");
csvPath=fullfile(root,csvRelative); matPath=fullfile(root,matRelative);
% Content-addressed repeated publication may reuse only identical evidence.
if ~isfile(csvPath)
    sixgr.util.csvWriteTable(csvPath,resources,'PreserveSchema',true,'RoundTripNumericText',true);
end
saved=sixgr.util.csvReadTable(csvPath,'TextType','string');
assert(height(saved)==score.ComparedComplexValueCount && ...
    isequaln(saved.SubcarrierIndex0,resources.SubcarrierIndex0) && ...
    isequaln(saved.SymbolIndex0,resources.SymbolIndex0) && ...
    isequaln(saved.RxBranchIndex0,resources.RxBranchIndex0) && ...
    isequaln(saved.ReferencePortIndex0,resources.ReferencePortIndex0) && ...
    isequaln(saved.HReal,resources.HReal) && isequaln(saved.HImag,resources.HImag) && ...
    isequaln(saved.ReferenceHReal,resources.ReferenceHReal) && ...
    isequaln(saved.ReferenceHImag,resources.ReferenceHImag) && ...
    isequaln(saved.FrequencyUnmatchedReferenceHReal,resources.FrequencyUnmatchedReferenceHReal) && ...
    isequaln(saved.FrequencyUnmatchedReferenceHImag,resources.FrequencyUnmatchedReferenceHImag) && ...
    all(string(saved.ChannelEstimateObservationID)==observation), ...
    'sixgr:link:ChannelScoringCSVClosure','Published complex values must match the scored receiver resources.');
if ~isfile(matPath)
    sixgr.util.matSave(matPath,struct('Snapshot',snapshot,'ReferenceEvidence',evidence, ...
        'Resources',resources,'Score',score,'DesiredWaveformSHA256',hash, ...
        'FrequencyUnmatchedReferenceEvidence',unmatchedEvidence, ...
        'FrequencyUnmatchedScore',unmatchedScore), ...
        'UseArtifactStore',false);
end
row.ChannelEstimateResourcesCSV=string(csvRelative);
row.ChannelEstimateResourcesCSVSHA256=string(sixgr.phy.waveform.WaveformHash.file(csvPath));
row.ChannelEstimateMATFile=string(matRelative);
row.ChannelEstimateMATFileSHA256=string(sixgr.phy.waveform.WaveformHash.file(matPath));
end
