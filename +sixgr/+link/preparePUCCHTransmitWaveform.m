function [waveform, cfgOut, evidence] = preparePUCCHTransmitWaveform(tx, cfg, varargin)
%PREPAREPUCCHTRANSMITWAVEFORM Bind PUCCH power and TX RF before channel use.
%
% The typed PUCCH assignment owns the applied UE transmit power.  This
% boundary converts the generated waveform to the repository-wide sqrt(mW)
% sample convention, applies the YAML-authoritative PA exactly once through
% applyPowerContext, and then applies the remaining transmitter RF stages.
% Shared streams use ApplyNodeRF=false: retain linear power allocation here
% and apply the physical node's PA/RF once, after all contributors are summed.

p=inputParser;
p.addParameter('ApplyNodeRF',true,@(x)islogical(x)&&isscalar(x));
p.parse(varargin{:});
applyNodeRF=p.Results.ApplyNodeRF;

if ~(isstruct(tx) && isfield(tx,"Waveform") && isfield(tx,"Power") && ...
        isfield(tx,"OFDMInfo"))
    error("sixgr:phy:pucch:MissingTransmitPowerEvidence", ...
        "PUCCH transmit preparation requires waveform, OFDM and typed power evidence.");
end
if ~isstruct(cfg)
    error("sixgr:phy:pucch:MissingRuntimeConfiguration", ...
        "PUCCH transmit preparation requires the resolved runtime configuration.");
end

appliedPower_dBm = double(sixgr.util.structGet(tx, ...
    "Power.AppliedPowerdBm",NaN));
if ~(isscalar(appliedPower_dBm) && isfinite(appliedPower_dBm))
    error("sixgr:phy:pucch:InvalidPowerControlState", ...
        "Typed PUCCH power control did not provide a finite applied transmit power.");
end

txInfo = struct("OFDM",tx.OFDMInfo);
powerContext = sixgr.rf.PowerContext(cfg,"UL", ...
    "NumPorts",size(tx.Waveform,2));
powerContext.TotalTxPower_dBm = appliedPower_dBm;
powerContext.TotalTxPower_mW = 10.^(appliedPower_dBm/10);
powerContext.TotalTxPower_W = powerContext.TotalTxPower_mW*1e-3;
powerContext.TotalTxPowerSource = ...
    "typed_pucch_assignment_power_control_state";
powerContext.SignalSpecificPowerControl = true;
powerContext.SignalFamily = "PUCCH";
[waveform,powerContext] = sixgr.rf.applyPowerContext( ...
    tx.Waveform,cfg,"UL",txInfo,"PowerContext",powerContext,"ApplyPA",applyNodeRF);

cfgOut = sixgr.util.structSet(cfg, ...
    "lls6g.runtimePowerContext",powerContext);
sampleRateHz = double(sixgr.util.structGet(tx,"OFDMInfo.SampleRate",NaN));
if ~(isfinite(sampleRateHz) && sampleRateHz > 0)
    error("sixgr:phy:pucch:MissingSampleRate", ...
        "PUCCH transmitter RF execution requires a finite OFDM sample rate.");
end

if ~applyNodeRF
    evidence=struct('ContractVersion','sixgr.link.PUCCHTransmitContribution/v1', ...
        'SignalFamily','PUCCH','WaveformAmplitudeUnit','sqrt_mW', ...
        'PowerContext',powerContext,'AppliedPower_dBm',appliedPower_dBm, ...
        'TXRFExecutionStatus','deferred_until_node_composition', ...
        'ReferencePlane','pre_node_rf_transmitter_contribution');
    return;
end
rfOut = sixgr.rf.applyRFImpairmentChain(waveform,cfgOut, ...
    "SampleRateHz",sampleRateHz, ...
    "Direction","UL", ...
    "MeasurementPoint","tx_output", ...
    "Endpoint","tx", ...
    "StrictMutationRequired",false, ...
    "UseLegacyGlobalConfig",false, ...
    "ApplyPA",false, ...
    "ApplyADC",false);
waveform = cast(rfOut.Waveform,"like",waveform);
cfgOut = sixgr.util.structSet(cfgOut, ...
    "lls6g.txRFImpairmentReplay",rfOut.Replay);

[measuredPower_mW,~,measurementInfo] = ...
    sixgr.rf.measureActiveOFDMTotalPower(waveform,txInfo);
measuredPower_dBm = 10*log10(max(measuredPower_mW,realmin));
evidence = struct( ...
    "ContractVersion","sixgr.link.PUCCHTransmitBoundary/v2", ...
    "SignalFamily","PUCCH", ...
    "WaveformAmplitudeUnit","sqrt_mW", ...
    "PowerContext",powerContext, ...
    "AppliedPower_dBm",appliedPower_dBm, ...
    "MeasuredTxOutputPower_dBm",double(measuredPower_dBm), ...
    "MeasuredTxOutputPower_mW",double(measuredPower_mW), ...
    "MeasuredTxOutputPowerReferenceDomain",char(string( ...
        measurementInfo.ReferenceDomain)), ...
    "MeasuredTxOutputActiveSymbolCount",double( ...
        measurementInfo.ActiveSymbolCount), ...
    "PowerClosureError_dB",double(measuredPower_dBm-appliedPower_dBm), ...
    "TxOutputWaveformSHA256",sixgr.phy.pucch.PUCCHUtil.hash( ...
        [real(waveform(:)).' imag(waveform(:)).']), ...
    "TXRFReplay",rfOut.Replay, ...
    "TXRFRow",rfOut.Row, ...
    "TXRFExecutionStatus",string(sixgr.util.structGet( ...
        rfOut.Replay,"RFExecutionStatus","applied_or_identity")), ...
    "TXRFStageOrder",string(sixgr.util.structGet( ...
        rfOut.Replay,"RFStageOrder","")), ...
    "TXRFAppliedStageCount",double(sixgr.util.structGet( ...
        rfOut.Replay,"RFAppliedStageCount",0)));
end
