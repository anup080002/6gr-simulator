function [modStr, targetCodeRate, mcsIndex] = amcFromCQI(cqiIn, modDefault, tcrDefault, cfg)
%AMCFROMCQI Shared CQI-to-AMC mapping for scheduler and LLS closed loop.

if nargin < 2
    modDefault = "";
end
if nargin < 3
    tcrDefault = NaN;
end
if nargin < 4
    cfg = struct();
end

cqi = max(1, min(15, round(double(cqiIn))));

if localUseWaveformFadingAMC(cfg)
    modTable = { ...
        'QPSK', ...
        'QPSK', ...
        'QPSK', ...
        'QPSK', ...
        'QPSK', ...
        'QPSK', ...
        'QPSK', ...
        'QPSK', ...
        'QPSK', ...
        'QPSK', ...
        'QPSK', ...
        '16QAM', ...
        '16QAM', ...
        '16QAM', ...
        '16QAM'};
    tcrTable = [ ...
        0.12, ...
        0.12, ...
        0.12, ...
        0.25, ...
        0.25, ...
        0.25, ...
        0.25, ...
        0.25, ...
        0.35, ...
        0.35, ...
        0.35, ...
        0.20, ...
        0.20, ...
        0.20, ...
        0.20];
else
    modTable = { ...
        'QPSK', ...
        'QPSK', ...
        'QPSK', ...
        '16QAM', ...
        '16QAM', ...
        '16QAM', ...
        '64QAM', ...
        '64QAM', ...
        '64QAM', ...
        '64QAM', ...
        '64QAM', ...
        '64QAM', ...
        '64QAM', ...
        '64QAM', ...
        '64QAM'};
    tcrTable = [ ...
        78, ...
        193, ...
        449, ...
        378, ...
        490, ...
        616, ...
        466, ...
        567, ...
        666, ...
        772, ...
        772, ...
        772, ...
        772, ...
        772, ...
        772] ./ 1024;
end

modStr = modTable{cqi};
targetCodeRate = tcrTable(cqi);

if nargin >= 2 && strlength(string(modDefault)) > 0
    modOrderDefault = sixgr.l2.mac.SchedulerBase.modOrder(modDefault);
    modOrderMapped = sixgr.l2.mac.SchedulerBase.modOrder(modStr);
    if modOrderDefault < modOrderMapped
        modStr = char(string(modDefault));
    end
end
if nargin >= 3 && isfinite(double(tcrDefault)) && double(tcrDefault) > 0
    targetCodeRate = min(double(tcrDefault), targetCodeRate);
end

mcsIndex = sixgr.l2.mac.SchedulerBase.approxMCSIndex(modStr, targetCodeRate, cqi);
end

function tf = localUseWaveformFadingAMC(cfg)
backend = lower(char(string(sixgr.util.structGet(cfg, "system.phyBackend", ""))));
awgnOnly = logical(sixgr.util.structGet(cfg, "channel.awgnOnly", false));
channelModel = upper(char(string(sixgr.util.structGet(cfg, "channel.model", "AWGN"))));
fadingModel = upper(char(string(sixgr.util.structGet(cfg, "channel.fading.model", ""))));
delayProfile = upper(char(string(sixgr.util.structGet(cfg, "channel.delayProfile", ""))));
tdlProfile = upper(char(string(sixgr.util.structGet(cfg, "channel.tdlProfile", ""))));
cdlProfile = upper(char(string(sixgr.util.structGet(cfg, "channel.cdlProfile", ""))));
fadingEnabled = logical(sixgr.util.structGet(cfg, "channel.fading.enable", false));

isConcreteFading = startsWith(channelModel, "TDL") || startsWith(channelModel, "CDL") || ...
    startsWith(delayProfile, "TDL") || startsWith(delayProfile, "CDL") || ...
    startsWith(tdlProfile, "TDL-") || startsWith(cdlProfile, "CDL-") || ...
    strcmp(fadingModel, "TDL") || strcmp(fadingModel, "CDL");

tf = strcmp(backend, "waveform") && fadingEnabled && ~awgnOnly && isConcreteFading;
end
