function T=completeEmptyLinkTrialSchema(T)
% Retain typed, zero-row execution columns when no data grant was executed.
% This declares a CSV schema, not a measurement, lifecycle row or PHY pass.
assert(istable(T) && height(T)==0,'sixgr:link:NonemptySchemaCompletion', ...
    'Empty-schema completion must never manufacture values for actual trials.');
numeric=["EffectiveMCSIndex","EffectiveLayers","EffectiveRank","ScheduledMCSIndex", ...
    "PostEqualizationNoiseVariance","EVMProxySINR_dB","RuntimeChannelSeed", ...
    "RuntimeChannelAnglePathCount","RuntimeChannelCanonicalInputSamples", ...
    "RuntimeChannelAlignmentLookaheadSamples"];
text=["EffectiveModulation","ScheduledModulation","RuntimeChannelStateKey", ...
    "RuntimeChannelLinkKey","RuntimeChannelReciprocityDirection", ...
    "RuntimeChannelReciprocitySource","RuntimeChannelReciprocityApproximationMode", ...
    "RuntimeChannelAngleEvidenceSource","RuntimeChannelPathGainsSHA256", ...
    "ExecutionBackend","ApproximationMode","RunID","RunTag","ScenarioID","ConfigHash","ExecutionID"];
flags=["ScheduledOperatingPointMatchesTransmitted","RuntimeChannelReciprocityExact", ...
    "RuntimeChannelTransmitAndReceiveSwapped","RuntimeChannelAngleEvidenceAvailable", ...
    "RuntimeChannelAlignmentLookaheadExecutedOnFork","RuntimeChannelObjectClockExact", ...
    "FallbackFlag","PlaceholderFlag","FinalizedFlag"];
for field=numeric
    if ~ismember(field,string(T.Properties.VariableNames)), T.(field)=zeros(0,1); end
end
for field=text
    if ~ismember(field,string(T.Properties.VariableNames)), T.(field)=strings(0,1); end
end
for field=flags
    if ~ismember(field,string(T.Properties.VariableNames)), T.(field)=false(0,1); end
end
end
