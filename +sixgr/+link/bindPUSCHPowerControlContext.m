function [waveOut, pc, cfgOut, stateOut] = bindPUSCHPowerControlContext(waveIn, cfg, tx, grant, stateIn)
%BINDPUSCHPOWERCONTROLCONTEXT Resolve TS 38.213 PUSCH transmit power.
% This function does not scale the waveform.  It binds the resolved power
% to cfgOut so sixgr.rf.applyPowerContext remains the single scaling stage.
% Both desired and shared-slot interferer waveforms must call this function
% before that stage; otherwise their receiver samples occupy different
% absolute-power domains and MU-MIMO superposition is physically invalid.

waveOut = waveIn;
cfgOut = cfg;
if nargin < 5 || ~isstruct(stateIn)
    stateIn = struct();
end
stateOut = stateIn;
pc = struct( ...
    "Enabled", false, ...
    "Status", "disabled", ...
    "TxPower_dBm", NaN, ...
    "RequestedPower_dBm", NaN, ...
    "Pcmax_dBm", NaN, ...
    "PowerHeadroom_dB", NaN, ...
    "AmplitudeScale", 1, ...
    "MeasuredWaveformPower_dBm", NaN, ...
    "PowerClosureError_dB", NaN, ...
    "Clipped", false, ...
    "Pathloss_dB", NaN, ...
    "PathlossReferenceRS", "", ...
    "Source", "", ...
    "PathlossSource", "", ...
    "TPCCommandBits", NaN, ...
    "TPCDelta_dB", 0, ...
    "PreviousF_dB", double(sixgr.util.structGet(stateIn, "PreviousF_dB", 0)), ...
    "UpdatedF_dB", double(sixgr.util.structGet(stateIn, "PreviousF_dB", 0)), ...
    "AdjustmentMode", "", ...
    "FormulaIncludesMuFactor", false, ...
    "ScalingAuthority", "sixgr.rf.applyPowerContext_single_stage");

enabled = logical(sixgr.util.structGet(cfg, "phy.pusch.powerControl.enabled", ...
    sixgr.util.structGet(cfg, "phy.pusch.power_control.enabled", ...
    sixgr.util.structGet(cfg, "powerAndRF.puschPowerControlEnabled", false))));
pc.Enabled = enabled;
if ~enabled
    return;
end

userMeta = sixgr.util.structGet(cfg, "lls6g.userContext", struct());
pathloss_dB = localFirstFiniteScalar( ...
    sixgr.util.structGet(userMeta, "RuntimeServingPathloss_dB", []));
pc.Pathloss_dB = double(pathloss_dB);
pathlossSource = strtrim(string(sixgr.util.structGet(userMeta, ...
    "RuntimeServingPathlossSource", "")));
referenceRS = strtrim(string(sixgr.util.structGet(userMeta, ...
    "RuntimeServingPathlossReferenceRS", "")));
measurementId = strtrim(string(sixgr.util.structGet(userMeta, ...
    "RuntimeServingPathlossMeasurementId", "")));
requireMeasuredRS = logical(sixgr.util.structGet(cfg, ...
    "phy.pusch.powerControl.requireMeasuredReferenceRS", ...
    sixgr.util.structGet(cfg, ...
    "phy.pusch.power_control.require_measured_reference_rs", false)));
if ~(isfinite(pathloss_dB) && pathloss_dB >= 0)
    error("sixgr:pusch:PathlossMeasurementMissing", ...
        "Enabled PUSCH power control requires a finite runtime pathloss measurement; configured SNR cannot substitute for it.");
end
forbiddenPathlossSource = ["configured_snr","proxy","fallback","synthetic"];
if strlength(pathlossSource) == 0 || any(contains(lower(pathlossSource), forbiddenPathlossSource))
    error("sixgr:pusch:InvalidPathlossMeasurementSource", ...
        "PUSCH power control rejected pathloss source '%s'.", pathlossSource);
end
if requireMeasuredRS && (strlength(referenceRS) == 0 || strlength(measurementId) == 0)
    error("sixgr:pusch:PathlossReferenceSignalMeasurementMissing", ...
        ["This scenario requires causally consumed reference-signal pathloss, " + ...
         "but the runtime user context has no measurement identity or RS identity."]);
end
if strlength(referenceRS) == 0
    referenceRS = "runtime-pathloss-model-no-reference-rs";
end
pc.PathlossSource = char(pathlossSource);
pc.PathlossReferenceRS = char(referenceRS);

try
    mRB = numel(tx.PUSCH.PRBSet);
catch
    mRB = numel(double(sixgr.util.structGet(grant, "PRBSet", [])));
end
mRB = max(1, round(double(mRB)));

p0 = localFirstFiniteScalar( ...
    sixgr.util.structGet(cfg, "phy.pusch.powerControl.p0PUSCH_dBm", []), ...
    sixgr.util.structGet(cfg, "phy.pusch.powerControl.P0_PUSCH_dBm", []), ...
    sixgr.util.structGet(cfg, "phy.pusch.power_control.p0_pusch_dbm", []));
p0UE = localFirstFiniteScalar( ...
    sixgr.util.structGet(cfg, "phy.pusch.powerControl.p0UE_dB", []), ...
    sixgr.util.structGet(cfg, "phy.pusch.power_control.p0_ue_db", []));
alpha = localFirstFiniteScalar( ...
    sixgr.util.structGet(cfg, "phy.pusch.powerControl.alpha", []), ...
    sixgr.util.structGet(cfg, "phy.pusch.power_control.alpha", []));
if ~all(isfinite([p0 p0UE alpha]))
    error("sixgr:pusch:PowerControlConfigurationMissing", ...
        ["Enabled PUSCH power control requires explicit P0-PUSCH, P0-UE, " + ...
         "and alpha values from the resolved scenario configuration."]);
end
if ~(isscalar(alpha) && isfinite(alpha) && alpha >= 0 && alpha <= 1)
    error("sixgr:pusch:InvalidPowerControlAlpha", ...
        "Configured PUSCH power-control alpha must be finite in [0,1].");
end
pcmax = localFirstFiniteScalar( ...
    sixgr.util.structGet(cfg, "phy.pusch.powerControl.pcmax_dBm", []), ...
    sixgr.util.structGet(cfg, "phy.pusch.powerControl.Pcmax_dBm", []), ...
    sixgr.util.structGet(cfg, "powerAndRF.uePcmax_dBm", []), ...
    sixgr.util.structGet(cfg, "lls6g.resolvedConfig.power_and_rf_frontend.ue_pcmax_dbm", []));
deltaTF = localFirstFiniteScalar( ...
    sixgr.util.structGet(cfg, "phy.pusch.powerControl.deltaTF_dB", []), ...
    sixgr.util.structGet(cfg, "phy.pusch.power_control.delta_tf_db", []));
if ~all(isfinite([pcmax deltaTF]))
    error("sixgr:pusch:PowerControlConfigurationMissing", ...
        ["Enabled PUSCH power control requires explicit PCMAX and delta-TF " + ...
         "values from the resolved scenario configuration."]);
end
adjustmentMode = lower(strtrim(string(sixgr.util.structGet(cfg, ...
    "phy.pusch.powerControl.adjustmentMode", sixgr.util.structGet(cfg, ...
    "phy.pusch.power_control.adjustment_mode", "")))));
if adjustmentMode == "accumulation"
    adjustmentMode = "accumulated";
end
closedLoopAuthority = sixgr.util.structGet(cfg, ...
    "phy.pusch.powerControl.closedLoopEnabled", sixgr.util.structGet(cfg, ...
    "phy.pusch.power_control.closed_loop_enabled", []));
if isempty(closedLoopAuthority) || ~isscalar(closedLoopAuthority)
    error("sixgr:pusch:PowerControlConfigurationMissing", ...
        "Enabled PUSCH power control requires an explicit closed-loop enable authority.");
end
closedLoopEnabled = logical(closedLoopAuthority);
[tpcDelta_dB, tpcCommandBits, tpcSource] = ...
    localResolvePUSCHTPCCommand(grant, adjustmentMode, closedLoopEnabled);
previousF_dB = double(sixgr.util.structGet(stateIn, "PreviousF_dB", 0));

inputMeanPower = mean(sum(abs(double(waveIn)).^2, 2), "omitnan");
if ~(isfinite(inputMeanPower) && inputMeanPower > 0)
    error("sixgr:pusch:InvalidPowerControlWaveform", ...
        "PUSCH power control requires a finite nonzero production waveform.");
end
referenceWaveformPower_dB = 10 * log10(inputMeanPower);

try
    scsKHz = double(tx.Carrier.SubcarrierSpacing);
    cyclicPrefix = string(tx.Carrier.CyclicPrefix);
catch
    scsKHz = double(sixgr.util.structGet(cfg, "phy.carrier.SubcarrierSpacing", NaN));
    cyclicPrefix = string(sixgr.util.structGet(cfg, "phy.carrier.CyclicPrefix", "normal"));
end
try
    numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
        scsKHz, cyclicPrefix, "generic_waveform_test", "");
catch cause
    wrapped = MException("sixgr:pusch:InvalidPowerControlNumerology", ...
        "PUSCH power control requires a catalogued NR carrier numerology.");
    wrapped = addCause(wrapped, cause);
    throwAsCaller(wrapped);
end
mu = double(numerology.Mu);
resolved = sixgr.phy.ul.pusch.PUSCHPowerController.resolve( ...
    "LoopId", 0, ...
    "AdjustmentMode", adjustmentMode, ...
    "Mu", mu, ...
    "MRB", mRB, ...
    "P0Nominal_dBm", p0, ...
    "P0UE_dB", p0UE, ...
    "Alpha", alpha, ...
    "MeasuredPathloss_dB", pathloss_dB, ...
    "DeltaTF_dB", deltaTF, ...
    "PreviousF_dB", previousF_dB, ...
    "TPCDelta_dB", tpcDelta_dB, ...
    "PCMAX_dBm", pcmax, ...
    "ReferenceWaveformPower_dBm", referenceWaveformPower_dB, ...
    "PathlossReferenceRS", referenceRS);

pc.Status = "resolved_ts_38_213_exact_single_power_context_scaling";
pc.TxPower_dBm = double(resolved.AppliedPower_dBm);
pc.RequestedPower_dBm = double(resolved.RequestedPower_dBm);
pc.Pcmax_dBm = double(resolved.PCMAX_dBm);
pc.PowerHeadroom_dB = double(resolved.PowerHeadroom_dB);
pc.Clipped = logical(resolved.Clipped);
pc.TPCCommandBits = double(tpcCommandBits);
pc.TPCDelta_dB = double(tpcDelta_dB);
pc.TPCSource = char(tpcSource);
pc.PreviousF_dB = double(resolved.PreviousF_dB);
pc.UpdatedF_dB = double(resolved.UpdatedF_dB);
pc.AdjustmentMode = char(resolved.AdjustmentMode);
pc.Mu = double(resolved.Mu);
pc.MRB = double(resolved.MRB);
pc.FormulaIncludesMuFactor = logical(resolved.FormulaIncludesMuFactor);
pc.Source = char(string(resolved.Source) + ":" + pathlossSource);
pc.ConfiguredSNRSubstitution = false;

cfgOut = sixgr.util.structSet(cfgOut, "powerAndRF.ueTxPower_dBm", double(resolved.AppliedPower_dBm));
resolvedScenario = sixgr.util.structGet(cfgOut, "lls6g.resolvedConfig", []);
if isstruct(resolvedScenario) && ~isempty(fieldnames(resolvedScenario))
    cfgOut = sixgr.util.structSet(cfgOut, ...
        "lls6g.resolvedConfig.power_and_rf_frontend.ue_tx_power_dbm", ...
        double(resolved.AppliedPower_dBm));
end
stateOut.PreviousF_dB = double(resolved.UpdatedF_dB);
stateOut.UpdateCount = double(sixgr.util.structGet(stateIn, "UpdateCount", 0)) + double(closedLoopEnabled);
stateOut.LastTPCCommandBits = double(tpcCommandBits);
stateOut.LastTPCDelta_dB = double(tpcDelta_dB);
end

function [delta_dB, bits, source] = localResolvePUSCHTPCCommand(grant, adjustmentMode, closedLoopEnabled)
delta_dB = 0;
bits = NaN;
source = "closed_loop_disabled_zero_correction";
if ~closedLoopEnabled
    return;
end
directDelta = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "TPCDelta_dB", []), ...
    sixgr.util.structGet(grant, "DecodedTPCDelta_dB", []));
if isfinite(directDelta)
    delta_dB = double(directDelta);
    source = "decoded_grant_explicit_tpc_delta_db";
    return;
end
bits = localFirstFiniteScalar( ...
    sixgr.util.structGet(grant, "TPCCommandForPUSCH", []), ...
    sixgr.util.structGet(grant, "TPCCommand", []), ...
    sixgr.util.structGet(grant, "tpc", []), ...
    sixgr.util.structGet(grant, "DecodedDCIFields.tpc_command_for_pusch", []), ...
    sixgr.util.structGet(grant, "DCIFields.tpc_command_for_pusch", []));
if ~(isfinite(bits) && bits == round(bits) && bits >= 0 && bits <= 3)
    error("sixgr:pusch:DecodedTPCCommandMissing", ...
        "Closed-loop PUSCH power control requires a decoded 2-bit TPC command on the executed grant.");
end
bits = round(double(bits));
if adjustmentMode == "accumulated"
    mapping = [-1 0 1 3];
elseif adjustmentMode == "absolute"
    mapping = [-4 -1 1 4];
else
    error("sixgr:pusch:InvalidPowerAdjustmentMode", ...
        "PUSCH TPC mode must be accumulated or absolute.");
end
delta_dB = double(mapping(bits + 1));
source = "decoded_dci_pusch_tpc_2bit_ts_38_213";
end

function value = localFirstFiniteScalar(varargin)
value = NaN;
for idx = 1:nargin
    candidate = varargin{idx};
    if isempty(candidate) || ~(isnumeric(candidate) || islogical(candidate))
        continue;
    end
    candidate = double(candidate(:));
    hit = find(isfinite(candidate), 1, "first");
    if ~isempty(hit)
        value = double(candidate(hit));
        return;
    end
end
end
