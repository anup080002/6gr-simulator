function [variance,reference]=resolveAbsoluteReferenceNoiseVariance(replay)
% Consume an ORIGINAL noise-reference receipt, never current signal power.
% This verifies arithmetic/units/clock binding; the build-frozen reference
% identity is supplied by the original impairment owner, not reconstructed.
id='sixgr:link:AbsoluteReferenceNoiseReceipt';
assert(isstruct(replay)&&isscalar(replay)&& ...
    all(isfield(replay,{'NoiseOperatingMode','AbsoluteReferenceNoise','SampleRate_Hz'}))&& ...
    localText(replay.NoiseOperatingMode)=="absolute_reference_esn0",id, ...
    'Require the original absolute-reference noise replay.');
reference=replay.AbsoluteReferenceNoise;
required={'NoiseOperatingMode','WaveformAmplitudeUnit','Direction', ...
    'RequestedReferenceEsN0_dB','ReferenceEPRE_mW','ReferenceSubcarrierSpacing_Hz', ...
    'ReferenceBWPSubcarrierCount','NominalTxTotalPower_dBm','ReferencePathloss_dB', ...
    'NoisePSD_mWPerHz','SampleRate_Hz','SampleNoiseVariance_mW','Source', ...
    'ReferenceContractVersion','ReferenceContractSHA256','ReferenceModel','ReferencePoint', ...
    'ReferenceIsMeasured','ThermalNoiseApplied','NoiseFigureApplied', ...
    'ReferencePathlossEvaluatedThisCall','Classification','ResearchClass'};
assert(isstruct(reference)&&isscalar(reference)&&all(isfield(reference,required)), ...
    id,'Retain the complete original reference receipt.');
assert(localText(reference.NoiseOperatingMode)=="absolute_reference_esn0"&& ...
    localText(reference.WaveformAmplitudeUnit)=="sqrt_mW"&& ...
    any(localText(reference.Direction)==["DL","UL"])&& ...
    localText(reference.ReferenceContractVersion)=="sixgr.link.absolute_reference_noise/v1"&& ...
    localText(reference.Source)=="declared_nominal_full_bwp_unity_array_nrPathLoss_reference_not_measured"&& ...
    localText(reference.ReferenceModel)=="nominal_full_bwp_unity_array"&& ...
    localText(reference.ReferencePoint)=="declared_pre_fading_unity_array_receive_reference_before_RX_front_end"&& ...
    localText(reference.Classification)=="IMPLEMENTATION_POLICY"&& ...
    localText(reference.ResearchClass)=="optional_research_experiment",id, ...
    'A nominal absolute reference is not thermal noise, measured SINR or normalized Es.');
assert(~isempty(regexp(char(localText(reference.ReferenceContractSHA256)), ...
    '^[0-9a-fA-F]{64}$','once')),id,'Keep the original frozen-reference digest.');
for field=["ReferenceIsMeasured","ThermalNoiseApplied","NoiseFigureApplied", ...
        "ReferencePathlossEvaluatedThisCall"]
    value=reference.(field);
    assert(islogical(value)&&isscalar(value)&&~value,id, ...
        'Original %s must be scalar logical false; runtime cannot acquire that authority.',field);
end
for field=["RequestedReferenceEsN0_dB","ReferenceEPRE_mW","ReferenceSubcarrierSpacing_Hz", ...
        "ReferenceBWPSubcarrierCount","NominalTxTotalPower_dBm","ReferencePathloss_dB", ...
        "NoisePSD_mWPerHz","SampleRate_Hz","SampleNoiseVariance_mW"]
    localNumber(reference.(field));
end
localNumber(replay.SampleRate_Hz);
assert(reference.SampleRate_Hz==replay.SampleRate_Hz&&reference.SampleRate_Hz>0&& ...
    reference.ReferenceEPRE_mW>0&&reference.ReferenceSubcarrierSpacing_Hz>0&& ...
    reference.NoisePSD_mWPerHz>0&&reference.SampleNoiseVariance_mW>0&& ...
    reference.ReferencePathloss_dB>=0&&reference.ReferenceBWPSubcarrierCount>0&& ...
    mod(reference.ReferenceBWPSubcarrierCount,12)==0,id,'Invalid original sample/reference coordinates.');
unit=sixgr.util.structGet(replay,'PowerContextAmplitudeUnit', ...
    sixgr.util.structGet(replay,'WaveformAmplitudeUnit',''));
assert(localText(unit)=="sqrt_mW",id,'The actual samples must retain absolute sqrt(mW) units.');
direction=sixgr.util.structGet(replay,'PowerContextDirection', ...
    sixgr.util.structGet(replay,'WaveformLinkDirection',''));
assert(localText(direction)==localText(reference.Direction),id, ...
    'The executed receiver direction must match its frozen reference.');
epre=10^((reference.NominalTxTotalPower_dBm-reference.ReferencePathloss_dB- ...
    10*log10(reference.ReferenceBWPSubcarrierCount))/10);
psd=10^((10*log10(reference.ReferenceEPRE_mW)-reference.RequestedReferenceEsN0_dB- ...
    10*log10(reference.ReferenceSubcarrierSpacing_Hz))/10);
variance=reference.NoisePSD_mWPerHz*reference.SampleRate_Hz;
assert(isfinite(variance)&&variance>0&& ...
    abs(reference.ReferenceEPRE_mW-epre)<=1e-11*epre&& ...
    abs(reference.NoisePSD_mWPerHz-psd)<=1e-11*psd&& ...
    abs(reference.SampleNoiseVariance_mW-variance)<=1e-12*variance,id, ...
    'Original nominal EPRE, N0 and actual Fs must close without signal normalization.');
% This resolver also runs immediately BEFORE the original noise draw, when
% InjectedNoiseVariance may still be unavailable. Completion/publication
% owners separately require the actual injected value to equal variance.
end

function localNumber(x)
assert(isa(x,'double')&&isreal(x)&&isscalar(x)&&isfinite(x), ...
    'sixgr:link:AbsoluteReferenceNoiseReceipt','Require original finite real double scalars.');
end
function s=localText(x)
assert((ischar(x)&&isrow(x))||(isstring(x)&&isscalar(x)), ...
    'sixgr:link:AbsoluteReferenceNoiseReceipt','Require original scalar text.');
s=string(x);
assert(~ismissing(s)&&strlength(s)>0,'sixgr:link:AbsoluteReferenceNoiseReceipt', ...
    'Original source/identity text cannot be missing.');
end
