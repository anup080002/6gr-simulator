    out (1,1) struct
    options (1,1) struct
    tStart (1,1) uint64
end
if ~observation.isComplete()
    error("WAVEFORM:IncompleteObservation", ...
        "Broadcast reception is incomplete: received through %.0f, required through %.0f.", ...
        observation.ReceivedThroughSample, observation.EndSampleExclusive);
end
if observation.SampleRateHz ~= prepared.SampleRateHz || ...
        observation.EndSampleExclusive - observation.StartSample ~= prepared.NumSamples
    error("sixgr:link:BroadcastObservationLayoutMismatch", ...
        "The complete received capture must match the prepared broadcast sample rate and extent.");
end
if logical(options.UseRuntimeChannel) ~= logical(prepared.RuntimeChannelDeferred)
    error("sixgr:link:BroadcastObservationModeMismatch", ...
        "Completion must retain the preparation's runtime-channel authority.");
end
cfg = prepared.Config;
receiverCfg = prepared.ReceiverConfig;
tx = prepared.Tx;
runtimeTxWaveform = prepared.TransmitSamples;
if isfinite(options.RuntimeSlot)
    expectedStart = round(double(options.RuntimeSlot) * ...
        sixgr.time.slotDurationSec(cfg) * observation.SampleRateHz);
    if observation.StartSample ~= expectedStart
        error("sixgr:link:BroadcastObservationOriginMismatch", ...
            "Received broadcast starts at sample %.0f; its scheduled origin is %.0f.", ...
            observation.StartSample, expectedStart);
    end
end
out.ObservationStartSample = observation.StartSample;
out.ObservationEndSampleExclusive = observation.EndSampleExclusive;
