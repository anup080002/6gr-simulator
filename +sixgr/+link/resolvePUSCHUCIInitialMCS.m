function ref=resolvePUSCHUCIInitialMCS(cfg,grant,harqContext,isRetx,currentMCS)
% gNB-owned initial MCS reference. Never consult UE transmitter/state fields.
ref=struct('MCS',double(currentMCS),'Source',"current_new_tb_mcs",'ContextHash',"");
if isRetx
    ctx=sixgr.util.structGet(harqContext,'TransportBlockContext',struct());
    if isempty(fieldnames(ctx)), ctx=sixgr.util.structGet(harqContext,'HARQTBContext',struct()); end
    if isempty(fieldnames(ctx)), ctx=sixgr.util.structGet(grant,'HARQTBContext',struct()); end
    fields={'OriginalMCS','OriginalTargetCodeRate','TBSBits','RNTI','HARQProcessId', ...
        'NDI','NDIEpoch','CellId','UeId','Direction','HARQContextHash'};
    assert(isstruct(ctx) && isscalar(ctx) && all(isfield(ctx,fields)), ...
        'sixgr:link:PUSCHUCIHARQReferenceMissing', ...
        'Retransmitted UCI-on-PUSCH needs the gNB original TB context, not current MCS or UE metadata.');
    id=sixgr.util.structGet(grant,'HARQ.HarqID',sixgr.util.structGet(grant,'HARQ.HARQProcess',NaN));
    assert(string(ctx.Direction)=="UL" && ctx.RNTI==grant.RNTI && ...
        ctx.HARQProcessId==id && ctx.NDI==grant.HARQ.NDI && ...
        ctx.NDIEpoch==grant.HARQ.NDIEpoch && ctx.CellId==grant.ServingCell && ...
        ctx.UeId==grant.UEIndex && ...
        ctx.TBSBits==grant.TBSBits && strlength(string(ctx.HARQContextHash))>0, ...
        'sixgr:link:PUSCHUCIHARQReferenceMismatch','The retained gNB TB identity must match this retransmission.');
    ref.MCS=double(ctx.OriginalMCS);
    ref.Source="gnb_retained_original_tb_context";
    ref.ContextHash=string(ctx.HARQContextHash);
end
validateattributes(ref.MCS,{'double'},{'scalar','integer','>=',0,'<=',31});
p=sixgr.link.resolveMCSProfile(cfg.phy.pusch.mcsTable,ref.MCS);
assert(p.Valid,'sixgr:link:PUSCHUCIInitialMCSUndefined', ...
    'The initial MCS must have a defined rate in the installed MCS table.');
if isRetx
    assert(abs(ctx.OriginalTargetCodeRate-p.TargetCodeRate)<1e-12, ...
        'sixgr:link:PUSCHUCIHARQReferenceMismatch','Retained MCS/rate must agree with the installed table.');
end
end
