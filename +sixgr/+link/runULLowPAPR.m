function out=runULLowPAPR(cfg,varargin)
%RUNULLOWPAPR Compatibility facade for the canonical paired waveform study.
ip=inputParser;
ip.addParameter("Logger",[],@(x)isempty(x)||isa(x,"sixgr.core.Logger"));
ip.addParameter("NumFrames",8,@(x)isnumeric(x)&&isscalar(x)&&x>=1);
ip.parse(varargin{:});
try
    evidence=sixgr.phy.waveform.LowPAPRStudyRunner.run( ...
        cfg,round(double(ip.Results.NumFrames)));
catch exception
    if ~isempty(ip.Results.Logger)
        ip.Results.Logger.error("runULLowPAPR failed closed: "+string(exception.message));
    end
    rethrow(exception);
end
out=struct("Ok",true,"Skipped",false,"BER",0,"BLER",0, ...
    "Throughput_Mbps",NaN,"EVM_rms",evidence.EVM_DFT_pct/100, ...
    "PAPR_CP_dB",evidence.PAPR_CP_dB, ...
    "PAPR_DFTs_dB",evidence.PAPR_DFTs_dB, ...
    "PAPR_Gain_dB",evidence.PAPR_Gain_dB, ...
    "Notes","canonical localized DFT-s-OFDM; explicit zero windowing", ...
    "ExecutionBackend",evidence.ExecutionBackend, ...
    "ApproximationMode",evidence.ApproximationMode, ...
    "Evidence",evidence);
end
