function validateCSIRecoveryCadence(cfg)
% Reject an impossible periodic DL CQI recovery policy before PHY execution.
% This validates scheduler policy, not a 3GPP-mandated confirmation count.
% No field is corrected silently. Aperiodic feedback has no fixed cadence;
% UL SRS has its own producer calendar and is not governed by DL UCI here.
if ~logical(sixgr.util.structGet(cfg,'phy.csi.reportCSI',false)) || ...
        lower(string(sixgr.util.structGet(cfg,'phy.csi.reportTrigger',"")))~="periodic" || ...
        sixgr.link.resolveLinkAdaptationDomain(cfg,'DL')~="cqi"
    return;
end
disabled=["fixed","fixed_mcs","configured_fixed","disabled","off","none","false"];
if any(lower(string(sixgr.util.structGet(cfg,'phy.linkAdaptation.mode',"fixed")))==disabled) || ...
        any(lower(string(sixgr.util.structGet(cfg,'phy.linkAdaptation.dlPolicy',"fixed")))==disabled)
    return;
end
required=double(sixgr.util.structGet(cfg,'phy.linkAdaptation.outageRecoveryPositiveCQIReports',1));
if required<=1, return; end
period=double(sixgr.util.structGet(cfg,'phy.csi.reportPeriodicitySlots',NaN));
gap=double(sixgr.util.structGet(cfg,'phy.linkAdaptation.outageRecoveryMaxGapSlots',Inf));
assert(isscalar(period) && isfinite(period) && period>=1 && period==fix(period), ...
    'sixgr:link:InvalidCSIRecoveryPeriod', ...
    'Periodic CQI recovery requires an explicit positive-integer phy.csi.reportPeriodicitySlots.');
assert(isscalar(gap) && gap>=period, ...
    'sixgr:link:CSIRecoveryCadenceConflict', ...
    ['link_adaptation.outage_recovery_max_gap_slots (phy.linkAdaptation.outageRecoveryMaxGapSlots) ' ...
    'is %g, below csi_acquisition_and_reporting.csi_report_periodicity_slots ' ...
    '(phy.csi.reportPeriodicitySlots)=%g. Requiring %g positive reports can never ' ...
    'recover from CQI 0 at that cadence. Configure a gap >= %g slots; do not bypass confirmation.'], ...
    gap,period,required,period);
end
