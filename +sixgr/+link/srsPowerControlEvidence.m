function fields=srsPowerControlEvidence(power)
% Stable producer-to-CSV schema; absent evidence is never a zero power.
if nargin<1, power=struct(); end
fields=struct();
mapping={ ...
    'AppliedPower_dBm','AppliedPower_dBm',NaN; ...
    'RequestedPower_dBm','RequestedPower_dBm',NaN; ...
    'PCMAX_dBm','PCMAX_dBm',NaN; ...
    'Pathloss_dB','MeasuredPathloss_dB',NaN; ...
    'PathlossSource','PathlossSource',""; ...
    'PathlossReferenceRS','Reference.ReferenceRS',""; ...
    'PathlossMeasurementId','Reference.MeasurementId',""; ...
    'PathlossProducerSlot','Reference.ProducerSlot',NaN; ...
    'PathlossAvailableSlot','Reference.AvailableSlot',NaN; ...
    'SignalledReferencePower_dBm','Reference.SignalledReferencePower_dBm',NaN; ...
    'FilteredRSRP_dBm','Reference.FilteredRSRP_dBm',NaN; ...
    'SIB1RxTreeHash','Reference.SIB1RxTreeHash',""; ...
    'MRB','MRB',NaN; 'Mu','Mu',NaN; ...
    'P0_dBm','Request.P0_dBm',NaN; 'Alpha','Request.Alpha',NaN; ...
    'DeltaTF_dB','Request.DeltaTF_dB',NaN; ...
    'BandwidthTerm_dB','BandwidthTerm_dB',NaN; ...
    'Adjustment_dB','AccumulatedTPC_dB',NaN; ...
    'AdjustmentState','AdjustmentState',""; ...
    'StateOwner','StateOwner',""; ...
    'StateUpdateCount','StateUpdateCount',NaN; ...
    'StateResetReason','StateResetReason',""; ...
    'ReceivedAssignmentDigest','ReceivedAssignmentDigest',""; ...
    'TPCAvailableAtSample','TPCAvailableAtSample',NaN; ...
    'TPCAppliedAtSample','TPCAppliedAtSample',NaN; ...
    'AdjustmentReadAtSample','AdjustmentReadAtSample',NaN; ...
    'BoundAtEmission','BoundAtEmission',false; ...
    'Clipped','Clipped',false};
for k=1:size(mapping,1)
    fields.(['SRSPowerControl' mapping{k,1}])= ...
        sixgr.util.structGet(power,mapping{k,2},mapping{k,3});
end
% These are the request actually consumed and the controller's recorded
% bandwidth operand, not values reconstructed from scenario defaults.
for name=["P0_dBm","Alpha","DeltaTF_dB","MRB","Mu","BandwidthTerm_dB"]
    raw=fields.("SRSPowerControl"+name);
    assert(isnumeric(raw)&&isreal(raw)&&isscalar(raw)&&(isfinite(raw)||isnan(raw)), ...
        'sixgr:link:SRSPowerOperandEvidence','Retain original scalar SRS power operands.');
end
fields.SRSPowerControlDeltaTFRole="";
if ~isnan(fields.SRSPowerControlDeltaTF_dB)
    assert(fields.SRSPowerControlDeltaTF_dB==0,'RF:SRSDeltaTFNotApplicable', ...
        'SRS has no PUSCH DeltaTF term; retain only the actual zero common-request operand.');
    fields.SRSPowerControlDeltaTFRole="not_applicable_SRS_common_request_zero_only";
end
end
