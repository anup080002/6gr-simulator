function outcome=resolveULHARQReceiverOutcome(current,combined)
% Select actual decoded bits by receiver CRC, never by transmitted content.
% Combined decoding is attempted only after a current-window CRC rejection.
assert(isstruct(current) && isscalar(current) && ...
    all(isfield(current,{'Ok','TransportBlock'})) && ...
    islogical(current.Ok) && isscalar(current.Ok), ...
    'sixgr:link:ULReceiverVerdictRequired','Retain the explicit current receiver CRC decision and decoded TB.');
bits=localBits(current.TransportBlock);
pass=current.Ok;
usedCombined=false;
if ~isempty(combined)
    assert(~current.Ok && isstruct(combined) && isscalar(combined) && ...
        all(isfield(combined,{'CRCPass','TransportBlock'})) && ...
        islogical(combined.CRCPass) && isscalar(combined.CRCPass), ...
        'sixgr:link:ULCombinedVerdictRequired', ...
        'Use an actual combined decoder verdict only after a current CRC rejection.');
    combinedBits=localBits(combined.TransportBlock);
    assert(numel(combinedBits)==numel(bits),'sixgr:link:ULDecodedTBSMismatch', ...
        'Current and combined decoding must retain the same scheduled TB length.');
    pass=combined.CRCPass;
    if pass
        bits=combinedBits;
        usedCombined=true;
    end
end
outcome=struct('CurrentDecodeOK',current.Ok,'CombinedDecodeOK',pass, ...
    'DecodedTransportBlockBits',bits,'SelectedCombinedDecode',usedCombined, ...
    'Source',"received_current_and_combined_CRC_not_TX_reference_match");
end

function bits=localBits(value)
assert((isnumeric(value)||islogical(value)) && isreal(value) && isvector(value) && ...
    ~isempty(value) && all(isfinite(value(:))) && all(value(:)==0|value(:)==1), ...
    'sixgr:link:ULDecodedBitsRequired','Retain a nonempty finite binary decoded TB before conversion.');
bits=int8(value(:));
end
