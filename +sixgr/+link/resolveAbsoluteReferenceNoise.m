function [variance,receipt,capsule]=resolveAbsoluteReferenceNoise(cfg,direction,sampleRateHz,varargin)
%RESOLVEABSOLUTEREFERENCENOISE Frozen absolute nominal-reference Es/N0.
% BUILD ONLY: Freeze=true evaluates nrPathLoss ONCE, for a declared reference
% geometry, and returns a capsule covering both directions. Runtime calls
% require that capsule and never consume received samples, instantaneous
% fading, selected rank/beam, UL power-control state or a scheduled budget.
% This is a simulation noise-reference definition, not a 3GPP-mandated noise
% calibration, measured SINR, thermal-noise model or RF conformance result.
ip=inputParser;
ip.addParameter('Freeze',false,@(x)islogical(x)&&isscalar(x));
ip.parse(varargin{:});
id='sixgr:link:AbsoluteReferenceNoise';
assert(isstruct(cfg)&&isscalar(cfg),id,'Supply one resolved configuration.');
assert(localText(sixgr.util.structGet(cfg,'run.noiseOperatingMode',''))=="absolute_reference_esn0", ...
    id,'This resolver requires run.noiseOperatingMode=absolute_reference_esn0.');
assert(~sixgr.rf.isFixedSNRLinkAuthority(cfg)&& ...
    sixgr.rf.fixedSNRPowerReferenceMode(cfg)=="absolute_calibrated_sqrt_mw", ...
    id,'Keep absolute sqrt(mW) samples and physical propagation; normalized fixed-SNR authority is incompatible.');
authority=sixgr.util.structGet(cfg,'integration.configured_snr_is_link_authority',[]);
assert(localText(sixgr.util.structGet(cfg,'integration.run_mode',''))=="GEOMETRY_NETWORK"&& ...
    islogical(authority)&&isscalar(authority)&&~authority, ...
    id,'Require explicit GEOMETRY_NETWORK with configured_snr_is_link_authority=false.');
direction=localText(direction);
assert(any(direction==["DL","UL"]),id,'Direction must be exactly DL or UL.');
localPositive(sampleRateHz,'actual sample rate');
binding=localBinding(cfg);
if ip.Results.Freeze
    assert(isempty(sixgr.util.structGet(cfg,'run.absoluteReferenceNoise',[])), ...
        id,'A frozen noise reference cannot be silently replaced. Build a fresh independent point.');
    p=binding.Policy;
    plc=nrPathLossConfig('Scenario',char(p.reference_pathloss_scenario));
    plc.EnvironmentHeight=binding.ReferenceEnvironmentHeight_m;
    plc.OptionalModel=false;
    loss=nrPathLoss(plc,binding.CarrierFrequency_Hz,p.reference_los, ...
        p.reference_bs_position_m(:),p.reference_ue_position_m(:));
    localFinite(loss,'native reference pathloss');
    assert(loss>=0,id,'Reference pathloss must be nonnegative.');
    capsule=struct('ContractVersion',"sixgr.link.absolute_reference_noise/v1", ...
        'Source',"declared_nominal_full_bwp_unity_array_nrPathLoss_reference_not_measured", ...
        'Binding',binding,'ReferencePathloss_dB',double(loss), ...
        'ReferencePathlossSource',"nrPathLoss_on_explicit_reference_geometry_once_at_configuration_build", ...
        'NativePathlossEvaluationCount',1,'ReferenceIsMeasured',false, ...
        'ThermalNoiseApplied',false,'ArrayGainIncluded',false, ...
        'FadingGainIncluded',false,'ScheduledPowerIncluded',false, ...
        'StandardizedAccuracyQualified',false,'HardwareQualified',false, ...
        'DL',localDirection(binding,loss,"DL"),'UL',localDirection(binding,loss,"UL"));
    capsule.SHA256=localHash(capsule);
else
    capsule=sixgr.util.structGet(cfg,'run.absoluteReferenceNoise',[]);
    required=["ContractVersion","Source","Binding","ReferencePathloss_dB", ...
        "ReferencePathlossSource","NativePathlossEvaluationCount","ReferenceIsMeasured", ...
        "ThermalNoiseApplied","ArrayGainIncluded","FadingGainIncluded", ...
        "ScheduledPowerIncluded","StandardizedAccuracyQualified","HardwareQualified","DL","UL","SHA256"];
    assert(isstruct(capsule)&&isscalar(capsule)&& ...
        isequal(sort(string(fieldnames(capsule))),sort(required(:)))&& ...
        localText(capsule.ContractVersion)=="sixgr.link.absolute_reference_noise/v1", ...
        id,'Require the complete original build-frozen noise-reference capsule.');
    assert(isequaln(capsule.Binding,binding)&& ...
        localText(capsule.SHA256)==localHash(rmfield(capsule,'SHA256')), ...
        id,'The frozen reference/configuration identity or digest changed.');
    localFinite(capsule.NativePathlossEvaluationCount,'original pathloss evaluation count');
    assert(capsule.NativePathlossEvaluationCount==1&& ...
        localText(capsule.Source)=="declared_nominal_full_bwp_unity_array_nrPathLoss_reference_not_measured"&& ...
        localText(capsule.ReferencePathlossSource)=="nrPathLoss_on_explicit_reference_geometry_once_at_configuration_build", ...
        id,'Retain the original reference model and one-time pathloss source.');
    for name=["ReferenceIsMeasured","ThermalNoiseApplied","ArrayGainIncluded", ...
            "FadingGainIncluded","ScheduledPowerIncluded","StandardizedAccuracyQualified","HardwareQualified"]
        flag=capsule.(name);
        assert(islogical(flag)&&isscalar(flag)&&~flag,id, ...
            'A nominal reference requires original scalar logical false for %s.',name);
    end
    localFinite(capsule.ReferencePathloss_dB,'frozen reference pathloss');
    assert(capsule.ReferencePathloss_dB>=0,id,'Reference pathloss must be nonnegative.');
    for d=["DL","UL"]
        assert(isequaln(capsule.(d),localDirection(binding,capsule.ReferencePathloss_dB,d)), ...
            id,'Frozen %s reference operands do not close.',d);
    end
end
d=capsule.(direction);
% Complex sample variance includes both quadratures. There is no extra 2,
% CP-overhead, antenna-count, rank, active-RE or instantaneous-power factor.
variance=d.NoisePSD_mWPerHz*double(sampleRateHz);
localPositive(variance,'resolved complex sample variance');
receipt=struct('NoiseOperatingMode',"absolute_reference_esn0", ...
    'WaveformAmplitudeUnit',"sqrt_mW",'Direction',direction, ...
    'RequestedReferenceEsN0_dB',binding.RequestedReferenceEsN0_dB, ...
    'ReferenceEPRE_mW',d.ReferenceEPRE_mW, ...
    'ReferenceSubcarrierSpacing_Hz',d.ReferenceSubcarrierSpacing_Hz, ...
    'ReferenceBWPSubcarrierCount',d.ReferenceBWPSubcarrierCount, ...
    'NominalTxTotalPower_dBm',d.NominalTxTotalPower_dBm, ...
    'ReferencePathloss_dB',capsule.ReferencePathloss_dB, ...
    'ReferenceEnvironmentHeight_m',binding.ReferenceEnvironmentHeight_m, ...
    'NoisePSD_mWPerHz',d.NoisePSD_mWPerHz,'SampleRate_Hz',double(sampleRateHz), ...
    'SampleNoiseVariance_mW',variance,'Source',capsule.Source, ...
    'ReferenceContractVersion',capsule.ContractVersion,'ReferenceContractSHA256',capsule.SHA256, ...
    'ReferenceModel',"nominal_full_bwp_unity_array", ...
    'ReferencePoint',"declared_pre_fading_unity_array_receive_reference_before_RX_front_end", ...
    'ReferenceIsMeasured',false,'ThermalNoiseApplied',false, ...
    'NoiseFigureApplied',false,'ReferencePathlossEvaluatedThisCall',ip.Results.Freeze, ...
    'Equation',"P_ref=P_nominal/(12*N_RB)*10^(-L_ref/10); N0=P_ref/(Delta_f*10^(EsN0/10)); sigma_complex_sample2=N0*Fs", ...
    'Classification',"IMPLEMENTATION_POLICY",'ResearchClass',"optional_research_experiment");
end

function b=localBinding(cfg)
id='sixgr:link:AbsoluteReferenceNoise';
p=sixgr.util.structGet(cfg,'run.absoluteReferenceNoisePolicy',[]);
names=["reference_policy","reference_pathloss_scenario","reference_bs_position_m", ...
    "reference_ue_position_m","reference_los","nominal_dl_tx_power_dbm", ...
    "nominal_ul_tx_power_dbm","classification"];
assert(isstruct(p)&&isscalar(p)&&isequal(sort(string(fieldnames(p))),sort(names(:))), ...
    id,'An explicit complete nominal reference policy is required; no geometry or budget default is inferred.');
assert(localText(p.reference_policy)=="nominal_full_bwp_unity_array"&& ...
    localText(p.classification)=="optional_research_experiment"&& ...
    localText(p.reference_pathloss_scenario)=="UMa", ...
    id,'Declare the supported UMa reference policy and optional research scope.');
for name=["reference_bs_position_m","reference_ue_position_m"]
    v=p.(name);
    assert(isa(v,'double')&&isreal(v)&&isvector(v)&&numel(v)==3&&all(isfinite(v)), ...
        id,'%s must contain three finite double coordinates in metres.',name);
    p.(name)=reshape(v,1,3);
end
distance=norm(p.reference_bs_position_m(1:2)-p.reference_ue_position_m(1:2));
assert(p.reference_bs_position_m(3)==25&& ...
    p.reference_ue_position_m(3)>=1.5&&p.reference_ue_position_m(3)<=22.5&& ...
    isfinite(distance)&&distance>=10&&distance<=5000, ...
    id,'Supported UMa reference domain: hBS=25 m, hUT=1.5..22.5 m, d2D=10..5000 m; no extrapolation.');
assert(islogical(p.reference_los)&&isscalar(p.reference_los),id,'Reference LOS must be an explicit boolean.');
localFinite(p.nominal_dl_tx_power_dbm,'nominal DL budget');
localFinite(p.nominal_ul_tx_power_dbm,'nominal UL budget');
fc=sixgr.util.structGet(cfg,'phy.fc_Hz',[]); localPositive(fc,'carrier frequency');
assert(fc>=0.5e9&&fc<=100e9,id,'The supported UMa reference frequency is 0.5..100 GHz.');
target=sixgr.util.structGet(cfg,'channel.snr_dB',[]); localFinite(target,'nominal reference Es/N0');
b=struct('Policy',p,'CarrierFrequency_Hz',double(fc), ...
    'RequestedReferenceEsN0_dB',double(target), ...
    'ReferenceEnvironmentHeight_m',1,'ReferenceOptionalPathlossModel',false);
for d=["DL","UL"]
    q=sixgr.util.structGet(cfg,'phy.bwp.'+lower(d),[]);
    assert(isstruct(q)&&isscalar(q)&&all(isfield(q, ...
        {'NSizeBWP','NStartBWP','SubcarrierSpacing_kHz','BWPID'})), ...
        id,'Require the original installed initial %s BWP, not allocated PRBs.',d);
    for name=["NSizeBWP","NStartBWP","SubcarrierSpacing_kHz","BWPID"]
        localFinite(q.(name),d+" BWP "+name);
    end
    assert(q.NSizeBWP>0&&q.NSizeBWP==fix(q.NSizeBWP)&&q.NStartBWP>=0&& ...
        q.NStartBWP==fix(q.NStartBWP)&&q.SubcarrierSpacing_kHz>0&& ...
        q.BWPID>=0&&q.BWPID==fix(q.BWPID),id,'Invalid installed reference BWP coordinates.');
    b.(d)=struct('BWPID',double(q.BWPID),'NSizeBWP',double(q.NSizeBWP), ...
        'NStartBWP',double(q.NStartBWP),'SubcarrierSpacing_Hz',1000*double(q.SubcarrierSpacing_kHz));
end
end

function d=localDirection(b,loss,direction)
p=b.Policy; q=b.(direction);
budget=p.("nominal_"+lower(direction)+"_tx_power_dbm");
k=12*q.NSizeBWP; scs=q.SubcarrierSpacing_Hz;
% Log-domain computation avoids separately overflowing nominal mW or gamma.
epreDbm=double(budget)-10*log10(k)-double(loss);
epre=10^(epreDbm/10);
psd=10^((epreDbm-b.RequestedReferenceEsN0_dB-10*log10(scs))/10);
localPositive(epre,'nominal reference EPRE'); localPositive(psd,'reference noise PSD');
d=struct('NominalTxTotalPower_dBm',double(budget),'ReferenceBWPSubcarrierCount',k, ...
    'ReferenceSubcarrierSpacing_Hz',scs,'ReferenceEPRE_dBm',epreDbm, ...
    'ReferenceEPRE_mW',epre,'NoisePSD_mWPerHz',psd);
end

function localFinite(x,name)
assert(isa(x,'double')&&isreal(x)&&isscalar(x)&&isfinite(x), ...
    'sixgr:link:AbsoluteReferenceNoise','%s must be a finite real double scalar.',name);
end
function localPositive(x,name)
localFinite(x,name);
assert(x>0,'sixgr:link:AbsoluteReferenceNoise','%s must be positive and representable.',name);
end
function s=localText(v)
assert((ischar(v)&&isrow(v))||(isstring(v)&&isscalar(v)), ...
    'sixgr:link:AbsoluteReferenceNoise','Expected scalar text, not a coercible numeric label.');
s=string(v);
assert(~ismissing(s)&&strlength(s)>0,'sixgr:link:AbsoluteReferenceNoise','Text must be nonempty.');
end
function h=localHash(v)
h=string(sixgr.util.sha256Hex(unicode2native(jsonencode(v),'UTF-8')));
end
