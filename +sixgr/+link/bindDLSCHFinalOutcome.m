function [trial,bound]=bindDLSCHFinalOutcome(trial,outcome)
%BINDDLSCHFINALOUTCOME Bind selected decoder verdicts to one original row.
% No decoding, payload comparison, MAC delivery or independent-population
% inference occurs here. CRC-negative completed decoder attempts are valid.
id='sixgr:link:DLSCHFinalOutcomeBinding';
assert(istable(trial)&&height(trial)==1 && ...
    all(ismember({'Frame','Slot','CRCPass'},trial.Properties.VariableNames)),id, ...
    'One original completed throughput row with its clock and CRC is required.');
for clockField=["Frame","Slot"]
    v=trial.(clockField);
    assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&isfinite(v)&&v>=0&&v==fix(v),id, ...
        'The original row coordinates must be explicit finite nonnegative integers.');
end
assert(isstruct(outcome)&&isscalar(outcome)&&all(isfield(outcome, ...
    {'ContractVersion','Stage','FinalThroughputOutcomeBound','NumCodewords','Codewords', ...
    'CRCPassPerCodeword','CRCPass','CRCError','OfferedBitsPerCodeword', ...
    'SuccessfulDecodedBitsPerCodeword','SuccessfulDecodedBits','DecodedBitsScope'})) && ...
    outcome.ContractVersion=="DLSCHFinalDecoderOutcome/v1" && ...
    outcome.Stage=="final_decoder_selection_before_completed_trial_binding" && ...
    isequal(outcome.FinalThroughputOutcomeBound,false),id, ...
    'Only an unbound original final decoder selection may be bound.');
n=double(outcome.NumCodewords);
assert(isscalar(n)&&any(n==[1 2])&&iscell(outcome.Codewords)&&numel(outcome.Codewords)==n,id, ...
    'The exact codeword population must be retained.');
pass=false(1,n); offered=zeros(1,n);
for k=1:n
    c=outcome.Codewords{k};
    assert(isstruct(c)&&isscalar(c)&&all(isfield(c, ...
        {'ContractVersion','CodewordIndex','CodewordIndexBase','NumCodewords', ...
        'CRCPass','CRCError','TransportBlockSize','DecodedTransportBlockLength', ...
        'DecodedTransportBlockSHA256','SuccessfulDecodedBits'})) && ...
        c.ContractVersion=="DLSCHFinalCodewordDecision/v1" && ...
        isequal(c.CodewordIndex,k-1)&&isequal(c.CodewordIndexBase,0)&&isequal(c.NumCodewords,n)&& ...
        islogical(c.CRCPass)&&isscalar(c.CRCPass)&&isequal(c.CRCError,~c.CRCPass)&& ...
        isnumeric(c.TransportBlockSize)&&isscalar(c.TransportBlockSize)&& ...
        isfinite(c.TransportBlockSize)&&c.TransportBlockSize>0&&c.TransportBlockSize==fix(c.TransportBlockSize)&& ...
        c.DecodedTransportBlockLength==c.TransportBlockSize && ...
        isscalar(string(c.DecodedTransportBlockSHA256))&&strlength(string(c.DecodedTransportBlockSHA256))==64,id, ...
        'Original per-codeword identities, lengths and verdicts are required.');
    pass(k)=c.CRCPass; offered(k)=double(c.TransportBlockSize);
    assert(isequal(c.SuccessfulDecodedBits,offered(k)*double(pass(k))),id, ...
        'Successful decoded bits must follow that codeword CRC only.');
end
assert(isequal(outcome.CRCPassPerCodeword,pass)&&isequal(outcome.CRCPass,all(pass))&& ...
    isequal(outcome.CRCError,any(~pass))&&isequal(outcome.OfferedBitsPerCodeword,offered)&& ...
    isequal(outcome.SuccessfulDecodedBitsPerCodeword,offered.*double(pass))&& ...
    isequal(outcome.SuccessfulDecodedBits,sum(offered.*double(pass))),id, ...
    'Aggregate aliases cannot replace or contradict the original individual verdicts.');
crc=trial.CRCPass;
assert((islogical(crc)||isnumeric(crc))&&isscalar(crc)&&isfinite(crc)&& ...
    any(crc==[0 1])&&logical(crc)==all(pass),id, ...
    'The completed row CRC must equal the selected per-codeword conjunction.');
% OfferedBits can correctly be zero on a retransmission (no newly offered
% traffic). It is not the per-attempt decoder population measured here.
if ismember('BitsCompared',trial.Properties.VariableNames)
    assert(isequal(double(trial.BitsCompared),sum(offered)),id, ...
        'The scored decoded population must equal the original transport-block lengths.');
end
for flag=["DecodeAttempted","DLSCHDecodeAttempted"]
    if ismember(flag,string(trial.Properties.VariableNames))
        v=trial.(flag); assert((islogical(v)||isnumeric(v))&&isscalar(v)&&isequal(double(v),1),id, ...
            'An explicitly unattempted row cannot carry a final decoder receipt.');
    end
end
if ismember('Crash',trial.Properties.VariableNames)
    assert(isequal(double(trial.Crash),0),id,'A crashed row is not a completed decoder outcome.');
end
if ismember('Direction',trial.Properties.VariableNames)
    assert(isequal(string(trial.Direction),"DL"),id,'DL-SCH outcomes cannot bind an uplink row.');
end
identityNames=["Direction","Frame","Slot","SFN","SlotConvention","AbsoluteSlot", ...
    "SNR_dB","ConfiguredSNR_dB","Seed","RandomSeed","ChannelSeed","SweepPointIndex", ...
    "UEIndex","UEID","RNTI","BaseStationID","ServingCell","GrantContextId", ...
    "FrozenGrantContextId","AssignmentId","AssignmentValidationDigest","DecodedDCIId", ...
    "ReceivedAssignmentDigest","HARQProcess","NDI","NDIEpoch","TBId","RV", ...
    "ReceiverObservationSHA256","ReceiverObservationHashPlane","ObservationStartSample", ...
    "ObservationEndSampleExclusive","ObservationSampleRateHz","Source", ...
    "ExecutionProfile","ExecutionBackend","RuntimeEvidenceSource","ApproximationMode"];
names=identityNames(ismember(identityNames,string(trial.Properties.VariableNames)));
bound=outcome;
bound.Stage="completed_throughput_decoder_outcome";
bound.FinalThroughputOutcomeBound=true;
bound.SourceRow=table2struct(trial(:,cellstr(names)));
bound.AggregateGoodBitsPolicy="all_codewords_CRC_pass_required_existing_throughput_policy";
bound.SuccessfulDecodedBitsPolicy="sum_of_individually_CRC_passing_TB_bits_this_attempt";
bound.OfferedBitsPerCodewordScope="coded_TB_bits_in_this_attempt_not_new_traffic_offered_load";
bound.MACDeliveryQualified=false;
token=string(jsonencode(bound)); digest=string(sixgr.util.sha256Hex(char(token)));
values=struct('DLSCHFinalOutcomeAvailable',true, ...
    'DLSCHFinalOutcomeStage',bound.Stage,'DLSCHFinalOutcomeJSON',token, ...
    'DLSCHFinalOutcomeSHA256',digest, ...
    'DLSCHSuccessfulDecodedBits',bound.SuccessfulDecodedBits, ...
    'DLSCHSuccessfulDecodedBitsScope',bound.DecodedBitsScope, ...
    'DLSCHAggregateGoodBitsPolicy',bound.AggregateGoodBitsPolicy);
for name=string(fieldnames(values)).'
    if ismember(name,string(trial.Properties.VariableNames))
        assert(isequaln(trial.(name),values.(name)),id,'An existing final receipt cannot be replaced.');
    end
    trial.(name)=values.(name);
end
end
