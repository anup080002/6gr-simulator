function [combined,evidence]=receivedDLHARQCombiningEvidence(rx)
% Project one canonical decode's evidence; never combine/decode a second time.
assert(isstruct(rx) && string(rx.ExecutionProfile)=="connected_strict" && ...
    string(rx.SchedulingOwnership)=="received_control_and_ue_owned_harq" && ...
    rx.DecoderCRCInputDomain=="harq_combined_mother_code", ...
    'sixgr:link:ReceivedDLHARQEvidenceAuthority','Only canonical received-control evidence is accepted.');
assert(isfield(rx,'Decode') && isstruct(rx.Decode) && isscalar(rx.Decode) && ...
    isfield(rx.Decode,'ContractVersion') && ...
    string(rx.Decode.ContractVersion)=="ExplicitDLSCHDecodeCodeword/v1" && ...
    isfield(rx.Decode,'CodewordIndex') && isequal(double(rx.Decode.CodewordIndex),0), ...
    'sixgr:link:ReceivedDLHARQCodewordScope', ...
    'Connected received DCI/HARQ currently authorizes one codeword only; aggregate aliases are not a second codeword contract.');
assert(isequaln(rx.RecLLR,rx.Decode.RateRecoveredLLR) && ...
    isequaln(rx.HARQCombinedLLR,rx.Decode.HARQCombinedLLR), ...
    'sixgr:link:ReceivedDLHARQEvidenceMismatch','Current and combined soft domains must match the actual decode.');
info=rx.Decode.HARQCombineInfo;
combined=rx.Decode.HARQCombinedLLR;
evidence=struct('PreviousLLRCount',info.PriorNumel, ...
    'CurrentLLRCount',info.CurrentNumel,'CombinedLLRCount',info.CombinedNumel, ...
    'CombiningApplied',info.Applied,'CombiningSkipReason',char(info.Reason), ...
    'PositionAware',info.PositionAware,'SoftBuffer',rx.Decode.SoftBuffer, ...
    'LLRCombiningGain_dB',info.LLRCombiningGain_dB);
assert(evidence.CurrentLLRCount==numel(rx.RecLLR) && ...
    evidence.CombinedLLRCount==numel(combined) && ~info.ResetPrior, ...
    'sixgr:link:ReceivedDLHARQEvidenceMismatch','Canonical combining counts or retention are inconsistent.');
end
