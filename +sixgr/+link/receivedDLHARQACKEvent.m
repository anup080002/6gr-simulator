function event=receivedDLHARQACKEvent(installed,a,decision,after)
% Bind an actual UE HARQ transition to its received connected DCI counter.
% No scheduler grant, expected TX bits or gNB feedback ledger is an input.
% The immutable post-transition entity is required; labels/ACK alone do not
% establish that this UE consumed the assignment. This creates a protocol
% event, not evidence that PUCCH/PUSCH was transmitted or received.
context=sixgr.phy.pdcch.validateConnectedAssignment(installed,a);
d=context.Data;
assert(a.Direction=="DL" && a.DCIFormat=="1_1" && d.DAIWidth==2 && ...
    d.DLReferenceSignaling.max_codewords==1 && a.NumLayers>=1 && a.NumLayers<=4 && ...
    d.ConnectedPolicy.harq_ack_codebook=="dynamic" && ...
    ~d.ConnectedPolicy.cross_carrier_scheduling && ~d.ConnectedPolicy.cbg_enabled && ...
    isempty(d.ConnectedPolicy.additional_dci_features), ...
    'sixgr:link:UnsupportedReceivedHARQEvent', ...
    'This event adapter requires ordinary single-cell, one-TB, two-bit-DAI connected DL.');
assert(isequal(installed.phy.harq.enable,true) && ...
    isa(after,'sixgr.link.ReceivedDLHARQState') && isscalar(after) && ...
    after.ContextDigest==context.Digest, ...
    'sixgr:link:ReceivedHARQEventStateRequired', ...
    'The post-transition UE-owned HARQ entity must match the received context.');
required={'IsRetransmission','DecodeAttempted','AcknowledgedFromPriorDecode', ...
    'ACK','DeliverTransportBlock','Source','FeedbackTransmissionQualified', ...
    'ReceivedAssignmentDigest','Attempt'};
assert(isstruct(decision) && isscalar(decision) && all(isfield(decision,required)), ...
    'sixgr:link:ReceivedHARQEventDecisionRequired','A complete UE HARQ decision is required.');
for name=required([1:5 7])
    assert(islogical(decision.(name{1})) && isscalar(decision.(name{1})), ...
        'sixgr:link:ReceivedHARQEventDecisionRequired','Decision flags must be scalar logical values.');
end
assert(isequal(string(decision.Source),"ue_received_control_and_actual_dl_decoder") && ...
    isequal(string(decision.ReceivedAssignmentDigest),string(a.AssignmentDigest)) && ...
    ~decision.FeedbackTransmissionQualified, ...
    'sixgr:link:ReceivedHARQEventDecisionRequired', ...
    'Decision provenance must bind this assignment without claiming transmitted feedback.');
index=localInteger(a.HARQProcess,0,numel(after.Processes)-1)+1;
attempt=localInteger(decision.Attempt,1,flintmax);
entry=after.Processes{index};
assert(isstruct(entry) && isscalar(entry) && ...
    entry.LastAssignmentDigest==a.AssignmentDigest && entry.NDI==a.NDI && ...
    entry.LastControlAbsoluteSlot==a.ControlAbsoluteSlot && ...
    entry.LastDataAbsoluteSlot==a.DataAbsoluteSlot && entry.Attempts==attempt && ...
    isequal(entry.Decoded,decision.ACK) && ...
    isequal(decision.IsRetransmission,attempt>1), ...
    'sixgr:link:ReceivedHARQEventStateMismatch', ...
    'The UE process must contain this exact consumed assignment, attempt and ACK state.');
assert(xor(decision.DecodeAttempted,decision.AcknowledgedFromPriorDecode) && ...
    (decision.DecodeAttempted && decision.DeliverTransportBlock==decision.ACK || ...
    decision.AcknowledgedFromPriorDecode && decision.ACK && ...
    decision.IsRetransmission && ~decision.DeliverTransportBlock), ...
    'sixgr:link:ReceivedHARQEventDecisionRequired', ...
    'Require an actual decode outcome or a retained ACK without duplicate TB delivery.');

rawDAI=localInteger(a.Fields.dai,0,3);
controlSlot=localInteger(a.ControlAbsoluteSlot,0,flintmax);
dataSlot=localInteger(a.DataAbsoluteSlot,controlSlot,flintmax);
k1=localInteger(a.K1Slots,0,flintmax);
feedbackSlot=localInteger(a.HARQFeedbackAbsoluteSlot,dataSlot,flintmax-1);
assert(feedbackSlot-dataSlot==k1, ...
    'sixgr:link:ReceivedHARQEventClockMismatch','Received data and feedback clocks must preserve K1.');
% The supported installed search space has one scalar starting symbol per
% monitored slot. The absolute-symbol clock is chronological, not modulo DAI
% and not a counter borrowed from the transmitter's scheduling history.
carrier=sixgr.phy.grid.makeCarrier(installed);
symbols=double(carrier.SymbolsPerSlot);
monitoring=installed.phy.pdcch.operatorControl.connected_monitoring;
sixgr.phy.pdcch.ConnectedPDCCHConfiguration.validatePolicy(monitoring);
start=localInteger(monitoring.start_symbol,0,symbols-1);
assert(controlSlot<=floor((flintmax-start)/symbols), ...
    'sixgr:link:ReceivedHARQEventClockMismatch','Monitoring clock exceeds exact integer range.');
monitoringClock=controlSlot*symbols+start;
state="NACK"; if decision.ACK, state="ACK"; end
data=struct('DAI',rawDAI+1,'CounterDAIRaw',rawDAI,'CounterDAIBits',2, ...
    'EventIndex',monitoringClock,'MonitoringOccasionIndex',monitoringClock, ...
    'MonitoringStartSymbol',start,'MonitoringClockDomain',"absolute_ofdm_symbol", ...
    'MonitoringConfigurationDigest',sixgr.phy.pucch.PUCCHUtil.hash(monitoring), ...
    'PDSCHID',"received-dl:"+string(a.AssignmentDigest), ...
    'Priority',0,'PrioritySource',"38.213_clause9_absent_priority_indicator", ...
    'ServingCell',double(d.ScheduledServingCell),'ServingCellDomain',"configured_serving_cell_index", ...
    'ComponentCarrier',double(d.ScheduledCarrier),'UEId',double(after.UEId), ...
    'State',state,'NumCodewords',1,'ConfigurationEpoch',double(a.ConfigurationEpoch), ...
    'RNTI',double(a.RNTI),'TargetSlot',feedbackSlot+1, ...
    'TargetSlotDomain',"one_based_absolute_slot", ...
    'ControlAbsoluteSlot',controlSlot,'DataAbsoluteSlot',dataSlot, ...
    'HARQFeedbackAbsoluteSlot',feedbackSlot,'K1Slots',k1, ...
    'HARQProcess',double(a.HARQProcess),'NDI',double(a.NDI),'Attempt',attempt, ...
    'PUCCHResourceIndicator',double(a.PUCCHResourceIndicator), ...
    'ReceivedAssignmentDigest',string(a.AssignmentDigest), ...
    'ReceivedContextDigest',string(a.ContextDigest),'ReceivedPayloadHash',string(a.PayloadHash), ...
    'DecodeAttempted',decision.DecodeAttempted, ...
    'AcknowledgedFromPriorDecode',decision.AcknowledgedFromPriorDecode, ...
    'DeliverTransportBlock',decision.DeliverTransportBlock, ...
    'FeedbackTransmissionQualified',false, ...
    'Source',"received_dci_and_ue_harq_transition");
% TS 38.213 18.8.0 clause 9: absent priority indication means priority 0.
% Clause 9.1.3 counter DAI field values 0..3 represent values 1..4.
event=sixgr.phy.pucch.HARQACKEvent(data);
end

function value=localInteger(raw,lower,upper)
assert(isnumeric(raw) && isreal(raw) && isscalar(raw) && isfinite(raw) && ...
    raw==fix(raw) && raw>=lower && raw<=upper, ...
    'sixgr:link:InvalidReceivedHARQEvent','Event integer is outside its exact supported range.');
value=double(raw);
end
