function row=scoreIndependentPDCCHReceiverEpisode(rx,info,expectedBits,execution)
% Score completed installed blind reception AFTER decoding. TX bits are
% scoring-only. Candidate/format hypotheses share one waveform denominator.
id='sixgr:link:UnmeasuredPDCCHReceiverEpisode';
assert(isstruct(rx)&&isscalar(rx)&&all(isfield(rx, ...
    {'Ok','DCIBits','AmbiguousValidHypotheses'})) && ...
    isstruct(info)&&isscalar(info)&&all(isfield(info, ...
    {'ReceiverConfiguredMonitoring','BlindSearch','NumCandidatesAvailable', ...
     'NumCandidatesTried','NumDecodeHypothesesTried','CandidateResults', ...
     'ExpectedDCIBits','ValidHypothesisCount','CRCValidHypothesisCount'})),id, ...
    'Retain actual completed connected receiver and candidate evidence.');
assert(isstruct(execution)&&isscalar(execution)&&all(isfield(execution, ...
    {'EpisodeID','SignalPresent','Scope','ChannelSeed','NoiseSeed','AbsoluteSlot0', ...
     'ReceiverOracleUsed','ReceiverCompleted','ExpectedCandidateCount', ...
     'MonitoredFormats','MonitoredPayloadSizes'})),id,'Execution identity is incomplete.');
for name=["SignalPresent","ReceiverOracleUsed","ReceiverCompleted"]
    assert(binary(execution.(name))&&isscalar(execution.(name)),id,'Invalid execution flag %s.',name);
end
assert(execution.ReceiverCompleted && ~execution.ReceiverOracleUsed && ...
    isequal(info.ReceiverConfiguredMonitoring,true) && isequal(info.BlindSearch,true) && ...
    isempty(info.ExpectedDCIBits),id,'No completed independent installed search was recorded.');
assert(binary(rx.Ok)&&isscalar(rx.Ok)&&binary(rx.AmbiguousValidHypotheses)&& ...
    isscalar(rx.AmbiguousValidHypotheses),id,'Receiver acceptance must be explicit.');
c=info.CandidateResults;
assert(istable(c)&&~isempty(c)&&all(ismember( ...
    ["CandidateFlatIndex","DCIFormat","DCIPayloadLength","DecodeAttempted", ...
     "CRCOK","ContextParseOK","DecodeOK","ErrFlag","PayloadHash"], ...
    string(c.Properties.VariableNames))),id,'Missing measured candidate hypotheses.');
for name=["DecodeAttempted","CRCOK","ContextParseOK","DecodeOK"]
    assert(binary(c.(name))&&isequal(size(c.(name)),[height(c) 1]),id, ...
        'Candidate %s must be one measured binary value per hypothesis.',name);
end
assert(all(c.DecodeAttempted) && all(isfinite(c.ErrFlag)&c.ErrFlag>=0&c.ErrFlag==fix(c.ErrFlag)) && ...
    isequal(logical(c.CRCOK),c.ErrFlag==0) && ...
    isequal(logical(c.DecodeOK),logical(c.CRCOK & c.ContextParseOK)),id, ...
    'Unattempted, missing or internally inconsistent decode is not a physical miss.');
n=execution.ExpectedCandidateCount; formats=string(execution.MonitoredFormats(:));
sizes=double(execution.MonitoredPayloadSizes(:));
assert(isnumeric(n)&&isscalar(n)&&isfinite(n)&&n>=1&&n==fix(n)&& ...
    numel(formats)==numel(sizes)&&numel(unique(formats))==numel(formats)&& ...
    info.NumCandidatesAvailable==n&&info.NumCandidatesTried==n&& ...
    info.NumDecodeHypothesesTried==height(c)&&height(c)==n*numel(formats),id, ...
    'The installed full search was not executed.');
for h=1:numel(formats)
    selected=string(c.DCIFormat)==formats(h);
    assert(isequal(sort(double(c.CandidateFlatIndex(selected))),(1:n).') && ...
        all(c.DCIPayloadLength(selected)==sizes(h)),id, ...
        'Each installed candidate/format/size hypothesis must occur exactly once.');
end
assert(info.ValidHypothesisCount==sum(c.DecodeOK)&& ...
    info.CRCValidHypothesisCount==sum(c.CRCOK)&& ...
    logical(rx.Ok)==(info.ValidHypothesisCount>0 && ~rx.AmbiguousValidHypotheses),id, ...
    'Receiver acceptance and retained hypothesis outcomes disagree.');
present=logical(execution.SignalPresent);
assert(binary(expectedBits) && present==~isempty(expectedBits),id, ...
    'H0 has no TX bits; H1 needs actual binary transmitted bits for post-RX scoring.');
matched=NaN; missed=NaN; wrongAccepted=NaN; falseCRC=NaN; falseAccepted=NaN;
if present
    assert(binary(rx.DCIBits)&&~isempty(rx.DCIBits),id,'Retain actual decoded bits even on CRC failure.');
    matched=logical(rx.Ok) && isequal(int8(rx.DCIBits(:)),int8(expectedBits(:)));
    missed=double(~matched); wrongAccepted=double(rx.Ok && ~matched);
else
    % Even a CRC pass rejected by the contextual parser is a physical false
    % CRC event. A chosen candidate must not disappear from this count.
    falseCRC=double(any(c.CRCOK)); falseAccepted=double(any(c.DecodeOK));
end
row=table(string(execution.EpisodeID),string(execution.Scope),present, ...
    execution.AbsoluteSlot0,execution.ChannelSeed,execution.NoiseSeed,n,height(c), ...
    sum(c.CRCOK),sum(c.DecodeOK),double(rx.Ok),double(matched),falseCRC,falseAccepted, ...
    missed,wrongAccepted,1,false,false,false, ...
    'VariableNames',{'EpisodeID','Scope','SignalPresent','AbsoluteSlot0', ...
    'ChannelSeed','NoiseSeed','CandidateCount','DecodeHypothesisCount', ...
    'CRCValidHypothesisCount','ContextValidHypothesisCount','ReceiverAccepted', ...
    'ExactPayloadRecovered','FalseCRCEpisode','FalseContextAcceptanceEpisode', ...
    'MissedPayloadEpisode','WrongPayloadAcceptanceEpisode','IndependentWaveformCount', ...
    'HypothesesAreIndependentTrials','StatisticallyQualified','ScenarioAccepted'});
end

function yes=binary(value)
yes=(isnumeric(value)||islogical(value))&&isreal(value)&& ...
    all(isfinite(value(:)))&&all(value(:)==0 | value(:)==1);
end
