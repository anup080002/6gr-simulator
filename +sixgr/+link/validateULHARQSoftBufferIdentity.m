function validateULHARQSoftBufferIdentity(prior,key)
% Reject foreign/unbound state before the existing position-aware combiner.
assert(isstring(key) && isscalar(key) && ~ismissing(key) && ...
    startsWith(key,"gNB-UL-TB-") && strlength(key)>10, ...
    'sixgr:link:ULHARQReceiverKeyRequired','Use the scheduled gNB receiver TB identity.');
if isempty(prior) || (isstruct(prior) && isscalar(prior) && isempty(fieldnames(prior)))
    return;
end
assert(isstruct(prior) && isscalar(prior) && ...
    all(isfield(prior,{'LLRSum','ObservationWeight','HARQKey','CodewordIndex'})), ...
    'sixgr:link:ULHARQUnboundPriorBuffer', ...
    'Independent shared UL combining requires its canonical receiver-owned soft buffer, not raw or anonymous LLRs.');
stored=prior.HARQKey;
assert((isstring(stored)&&isscalar(stored)) || (ischar(stored)&&isrow(stored)), ...
    'sixgr:link:ULHARQSoftBufferIdentityMismatch','Retain one explicit prior receiver key.');
assert(~ismissing(string(stored)) && string(stored)==key && ...
    isnumeric(prior.CodewordIndex) && isreal(prior.CodewordIndex) && ...
    isscalar(prior.CodewordIndex) && prior.CodewordIndex==1, ...
    'sixgr:link:ULHARQSoftBufferIdentityMismatch', ...
    'Prior soft state must match the scheduled UE/context/process/NDI epoch and codeword.');
end
