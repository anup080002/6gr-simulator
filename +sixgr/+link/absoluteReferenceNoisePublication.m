function fields=absoluteReferenceNoisePublication(replay)
% Preserve ORIGINAL controlled-noise evidence; never reconstruct from a target.
% Empty defaults are schema, not measurements. This helper does not set noise,
% estimate SINR, evaluate pathloss, or convert a nominal value into reception.
fields=struct('AbsoluteReferenceNoiseEvidenceAvailable',false, ...
    'RequestedReferenceEsN0_dB',NaN,'ReferenceNoisePSD_mWPerHz',NaN, ...
    'ReferenceNoiseSampleVariance_mW',NaN,'ReferenceNoiseSampleRate_Hz',NaN, ...
    'ReferenceNoiseContractSHA256',"",'ReferenceNoiseSource',"", ...
    'ReferenceNoiseReferencePlane',"",'ThermalNoiseApplied',NaN, ...
    'ControlledReferenceNoiseApplied',NaN, ...
    'AbsoluteReferenceNoiseInjectedSampleVariance_mW',NaN, ...
    'AbsoluteReferenceNoiseInjectionDomain',"", ...
    'AbsoluteReferenceNoiseJSON',"",'AbsoluteReferenceNoiseJSONSHA256',"");
if nargin==0, return; end
assert(isstruct(replay)&&isscalar(replay),'sixgr:link:AbsoluteReferenceNoisePublication', ...
    'Publication requires an original scalar replay or an empty schema.');
mode=string(sixgr.util.structGet(replay,'NoiseOperatingMode',''));
assert(isscalar(mode)&&~ismissing(mode),'sixgr:link:AbsoluteReferenceNoisePublication', ...
    'Noise mode must be original scalar text.');
if mode~="absolute_reference_esn0"
    original=sixgr.util.structGet(replay,'AbsoluteReferenceNoise',struct());
    assert(isstruct(original)&&isscalar(original)&&isempty(fieldnames(original)), ...
        'sixgr:link:AbsoluteReferenceNoisePublication', ...
        'An absolute-reference receipt cannot be published under another noise mode.');
    return;
end
[variance,original]=sixgr.link.resolveAbsoluteReferenceNoiseVariance(replay);
injected=sixgr.util.structGet(replay,'AbsoluteReferenceNoiseInjectedSampleVariance_mW',NaN);
domain=string(sixgr.util.structGet(replay,'AbsoluteReferenceNoiseInjectionDomain',''));
assert(isa(injected,'double')&&isreal(injected)&&isscalar(injected)&& ...
    isfinite(injected)&&injected>0&&abs(injected-variance)<=1e-12*variance&& ...
    isequal(domain,"receiver_sample_waveform_pre_composite_front_end"), ...
    'sixgr:link:AbsoluteReferenceNoisePublication', ...
    'Retain the original pre-front-end noise draw; effective receiver disturbance is not that draw.');
fields.AbsoluteReferenceNoiseInjectedSampleVariance_mW=injected;
fields.AbsoluteReferenceNoiseInjectionDomain=domain;
expected=struct('RequestedReferenceEsN0_dB',original.RequestedReferenceEsN0_dB, ...
    'ReferenceNoisePSD_mWPerHz',original.NoisePSD_mWPerHz, ...
    'ReferenceNoiseSampleVariance_mW',variance, ...
    'ReferenceNoiseSampleRate_Hz',original.SampleRate_Hz, ...
    'ReferenceNoiseContractSHA256',string(original.ReferenceContractSHA256), ...
    'ReferenceNoiseSource',string(original.Source), ...
    'ReferenceNoiseReferencePlane',string(original.ReferencePoint));
for field=string(fieldnames(expected)).'
    assert(isfield(replay,field),'sixgr:link:AbsoluteReferenceNoisePublication', ...
        'Original runtime field %s is missing; do not infer it at publication.',field);
    value=replay.(field);
    if isstring(expected.(field)), value=string(value); end
    assert(isa(value,class(expected.(field)))&&isequal(value,expected.(field)), ...
        'sixgr:link:AbsoluteReferenceNoisePublication', ...
        'Original runtime field %s disagrees with its original receipt.',field);
    fields.(field)=value;
end
thermal=sixgr.util.structGet(replay,'ThermalNoiseApplied',[]);
controlled=sixgr.util.structGet(replay,'ControlledReferenceNoiseApplied',[]);
assert(islogical(thermal)&&isscalar(thermal)&&~thermal&& ...
    islogical(controlled)&&isscalar(controlled)&&controlled, ...
    'sixgr:link:AbsoluteReferenceNoisePublication', ...
    'Controlled absolute noise must not claim thermal-noise execution.');
fields.ThermalNoiseApplied=0;
fields.ControlledReferenceNoiseApplied=1;
fields.AbsoluteReferenceNoiseEvidenceAvailable=true;
fields.AbsoluteReferenceNoiseJSON=string(jsonencode(original));
fields.AbsoluteReferenceNoiseJSONSHA256=string(sixgr.util.sha256Hex( ...
    char(fields.AbsoluteReferenceNoiseJSON)));
end
