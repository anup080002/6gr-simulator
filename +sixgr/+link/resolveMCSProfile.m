function profile = resolveMCSProfile(mcsTable, mcsIndex)
%RESOLVEMCSPROFILE Resolve a named MCS table/index into modulation and code rate.
%
%   PROFILE = sixgr.link.resolveMCSProfile(MCSTABLE, MCSINDEX) returns a
%   struct with fields:
%     Valid
%     Table
%     MCSIndex
%     Qm
%     Modulation
%     TargetCodeRate
%     SpectralEfficiency
%
% Supported tables follow TS 38.214 Section 5.1.3.1:
%   qam64_table1
%   qam256_table2
%   qam64LowSE_table3
% Catalog-defined experimental_* tables are explicitly labelled StandardNR=false.
% Their codepoints are lab policy, not standardized MCS or SINR calibration.

tableToken = lower(strtrim(string(mcsTable)));
idx = round(double(mcsIndex));

profile = struct( ...
    "Valid", false, ...
    "Table", char(tableToken), ...
    "MCSIndex", double(idx), ...
    "Qm", NaN, ...
    "Modulation", "", ...
    "TargetCodeRate", NaN, ...
    "SpectralEfficiency", NaN);

if ~(isscalar(idx) && isfinite(idx) && idx >= 0)
    return;
end

switch tableToken
    case "qam64_table1"
        Qm = [ ...
            2 2 2 2 2 2 2 2 2 2 ...
            4 4 4 4 4 4 4 ...
            6 6 6 6 6 6 6 6 6 6 6 6];
        R1024 = [ ...
            120 157 193 251 308 379 449 526 602 679 ...
            340 378 434 490 553 616 658 ...
            438 466 517 567 616 666 719 772 822 873 910 948];
        se = [ ...
            0.2344 0.3066 0.3770 0.4902 0.6016 0.7402 0.8770 1.0273 1.1758 1.3262 ...
            1.3281 1.4766 1.6953 1.9141 2.1602 2.4063 2.5703 ...
            2.5664 2.7305 3.0293 3.3223 3.6094 3.9023 4.2129 4.5234 4.8164 5.1152 5.3320 5.5547];
    case "qam256_table2"
        Qm = [ ...
            2 2 2 2 2 ...
            4 4 4 4 4 4 ...
            6 6 6 6 6 6 6 6 6 ...
            8 8 8 8 8 8 8 8];
        R1024 = [ ...
            120 193 308 449 602 ...
            378 434 490 553 616 658 ...
            466 517 567 616 666 719 772 822 873 ...
            682.5 711 754 797 841 885 916.5 948];
        se = [ ...
            0.2344 0.3770 0.6016 0.8770 1.1758 ...
            1.4766 1.6953 1.9141 2.1602 2.4063 2.5703 ...
            2.7305 3.0293 3.3223 3.6094 3.9023 4.2129 4.5234 4.8164 5.1152 ...
            5.3320 5.5547 5.8906 6.2266 6.5703 6.9141 7.1602 7.4063];
    case "qam64lowse_table3"
        Qm = [ ...
            2 2 2 2 2 2 2 2 2 2 2 2 2 2 2 ...
            4 4 4 4 4 4 ...
            6 6 6 6 6 6 6 6];
        R1024 = [ ...
            30 40 50 64 78 99 120 157 193 251 308 379 449 526 602 ...
            340 378 434 490 553 616 ...
            438 466 517 567 616 666 719 772];
        se = [ ...
            0.0586 0.0781 0.0977 0.1250 0.1523 0.1934 0.2344 0.3066 0.3770 0.4902 0.6016 0.7402 0.8770 1.0273 1.1758 ...
            1.3281 1.4766 1.6953 1.9141 2.1602 2.4063 ...
            2.5664 2.7305 3.0293 3.3223 3.6094 3.9023 4.2129 4.5234];
    otherwise
        definition=sixgr.phy.research.resolveExperimentalMCSTable(tableToken);
        if isempty(definition), return; end
        row=definition.Rows(definition.Rows(:,1)==idx,:);
        if isempty(row), return; end
        profile.Valid=true;
        profile.Qm=row(2);
        profile.Modulation=char(localQmToModulation(profile.Qm));
        profile.TargetCodeRate=row(3);
        profile.SpectralEfficiency=row(2)*row(3);
        profile.StandardNR=false;
        profile.ResearchClass=definition.ResearchClass;
        return;
end

if idx + 1 > numel(Qm)
    return;
end

profile.Valid = true;
profile.Qm = double(Qm(idx + 1));
profile.Modulation = char(localQmToModulation(profile.Qm));
profile.TargetCodeRate = double(R1024(idx + 1)) / 1024;
profile.SpectralEfficiency = double(se(idx + 1));
end

function modText = localQmToModulation(qm)
switch round(double(qm))
    case 2
        modText = "QPSK";
    case 4
        modText = "16QAM";
    case 6
        modText = "64QAM";
    case 8
        modText = "256QAM";
    case 10
        modText = "1024QAM";
    otherwise
        modText = "";
end
end
