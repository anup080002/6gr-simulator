function result=collectCSISelectionQualityEvidence(runRoot,trials)
%COLLECTCSISELECTIONQUALITYEVIDENCE Read existing private nominal diagnostics.
% No receiver, channel, noise or RF execution; no new objective or optimum.
% runRoot is the current artifact container (which may be a relocated copy).
% Original RunFolder/config/point identities remain unchanged and row-bound.
arguments
    runRoot {mustBeTextScalar}
    trials table
end
result=struct2table(localPrototype(),'AsArray',true); result=result([],:);
names=string(trials.Properties.VariableNames);
if ~ismember('CSISelectionQualityMATFile',names)
    if ismember('CSISelectionQualityAvailable',names)
        assert(~any(sixgr.truth.numericMeasurementColumn(trials.CSISelectionQualityAvailable,'CSISelectionQualityAvailable')==1), ...
            'sixgr:report:CSISelectionArchiveMissing','Available evidence requires its original archive.');
    end
    return;
end
root=string(java.io.File(char(runRoot)).getCanonicalPath());
seen=strings(0,1);
for index=1:height(trials)
    row=trials(index,:); relative=string(row.CSISelectionQualityMATFile);
    if ismissing(relative) || strlength(strtrim(relative))==0
        if ismember('CSISelectionQualityAvailable',names)
            assert(sixgr.truth.numericMeasurementColumn(row.CSISelectionQualityAvailable,'CSISelectionQualityAvailable')~=1, ...
                'sixgr:report:CSISelectionArchiveMissing','Available evidence cannot omit its archive.');
        end
        continue;
    end
    evidence=localRead(root,row); evidence.SourceRowIndex=index;
    assert(~any(seen==evidence.IdentitySHA256),'sixgr:report:CSISelectionDuplicateObservation', ...
        'A sealed observation must not be counted twice in one supplied population.');
    seen(end+1,1)=evidence.IdentitySHA256; %#ok<AGROW>
    result=[result;struct2table(evidence,'AsArray',true)]; %#ok<AGROW>
end
end

function out=localRead(root,row)
required=["CSISelectionQualityAvailable","CSISelectionQualityMATFileSHA256", ...
    "CSISelectionQualityCandidatesCSV","CSISelectionQualityCandidatesCSVSHA256", ...
    "CSISelectionQualityIdentityJSON","CSISelectionQualityIdentitySHA256", ...
    "CSISelectionQualityOperandSetSHA256"];
assert(all(ismember(required,string(row.Properties.VariableNames))) && ...
    sixgr.truth.numericMeasurementColumn(row.CSISelectionQualityAvailable,'CSISelectionQualityAvailable')==1, ...
    'sixgr:report:CSISelectionArchiveBinding','A declared archive requires complete available source binding.');
matPath=localPath(root,row.CSISelectionQualityMATFile,"mat");
csvPath=localPath(root,row.CSISelectionQualityCandidatesCSV,"csv");
localFileHash(matPath,row.CSISelectionQualityMATFileSHA256);
localFileHash(csvPath,row.CSISelectionQualityCandidatesCSVSHA256);
p=load(char(matPath));
fields=["Contract","Identity","IdentitySHA256","Inputs","SourceHashes", ...
    "OperandSetSHA256","SourceHashContract","Summary","Candidates","CandidateMatrices", ...
    "PublishedCandidates","CandidatesCSV","CandidatesCSVSHA256","EvidenceScope", ...
    "StatisticallyQualified"];
assert(all(isfield(p,fields)) && p.Contract=="sixgr_private_UE_CSI_selection_quality_archive/v1" && ...
    p.SourceHashContract=="sixgr_typed_plain_value_shape_and_exact_numeric_bytes/v1" && ...
    p.EvidenceScope=="private_UE_fixed_CRI_selection_quality_not_UCI_delivery_or_applied_grant" && ...
    isequal(p.StatisticallyQualified,false), ...
    'sixgr:report:CSISelectionArchiveSchema','Only the existing explicit private diagnostic contract is supported.');
assert(localDigest(p.Identity)==p.IdentitySHA256 && ...
    p.IdentitySHA256==string(row.CSISelectionQualityIdentitySHA256) && ...
    localDigest(p.SourceHashes)==p.OperandSetSHA256 && ...
    p.OperandSetSHA256==string(row.CSISelectionQualityOperandSetSHA256), ...
    'sixgr:report:CSISelectionArchiveChecksum','Original typed identity/operand seals disagree.');
for name=["Reference","Selection","Request","Disturbance","Policy"]
    assert(isfield(p.Inputs,name) && isfield(p.SourceHashes,name+"SHA256") && ...
        localDigest(p.Inputs.(name))==p.SourceHashes.(name+"SHA256"), ...
        'sixgr:report:CSISelectionArchiveChecksum','Original %s operand seal disagrees.',name);
end
stem="csi_selection_quality_"+string(p.IdentitySHA256);
assert(endsWith(replace(string(row.CSISelectionQualityMATFile),'\','/'),"/"+stem+".mat") && ...
    endsWith(replace(string(row.CSISelectionQualityCandidatesCSV),'\','/'),"/"+stem+".csv") && ...
    replace(string(p.CandidatesCSV),'\','/')==replace(string(row.CSISelectionQualityCandidatesCSV),'\','/') && ...
    p.CandidatesCSVSHA256==string(row.CSISelectionQualityCandidatesCSVSHA256), ...
    'sixgr:report:CSISelectionArchiveBinding','The two immutable files must address the same original observation.');
localOwner(row,p.Identity,p.Inputs);
localPlaneAndNoise(row,p.Inputs);
% Reuse the existing public scorer to validate its exact legal domain and
% contracts, then the producer's shared inverse-covariance arithmetic check.
% Neither consumes new measurements or changes the archived unit-power mode.
[summary,candidates]=sixgr.truth.scoreCSISelectionQuality(p.Inputs.Reference, ...
    p.Inputs.Selection,p.Inputs.Request,p.Inputs.Disturbance,p.Inputs.Policy);
assert(isequaln(summary,p.Summary) && isequaln(candidates,p.Candidates), ...
    'sixgr:report:CSISelectionArchiveRecompute','Saved results must equal the original declared scorer and complete legal domain.');
sixgr.truth.validateCSISelectionQualityArithmetic(p);
csv=sixgr.util.csvReadTable(csvPath,'TextType','string');
localCSV(csv,p);
localFileHash(matPath,row.CSISelectionQualityMATFileSHA256);
localFileHash(csvPath,row.CSISelectionQualityCandidatesCSVSHA256);
out=localPrototype(); out.DiagnosticAvailable=true;
out.Status="verified_existing_private_nominal_archive_not_accuracy_qualification";
out.IdentityJSON=string(row.CSISelectionQualityIdentityJSON);
out.IdentitySHA256=string(p.IdentitySHA256); out.OperandSetSHA256=string(p.OperandSetSHA256);
for name=string(fieldnames(p.Identity)).'
    if isfield(out,name), out.(name)=p.Identity.(name); end
end
out.PopulationScopeComplete=all(isfield(p.Identity,["RunID","ExecutionID","ConfigHash","ScenarioID", ...
    "RandomSeed","ChannelSeed","SweepPointIndex"]));
if out.PopulationScopeComplete
    lifecycle=[string(out.RunID),string(out.ExecutionID),string(out.ConfigHash),string(out.ScenarioID)];
    seeds=[out.RandomSeed,out.ChannelSeed]; point=out.SweepPointIndex;
    out.PopulationScopeComplete=all(~ismissing(lifecycle) & strlength(strtrim(lifecycle))>0) && ...
        isnumeric(seeds) && isreal(seeds) && isequal(size(seeds),[1 2]) && ...
        all(isfinite(seeds) & seeds>=0 & seeds<=double(intmax('uint32')) & seeds==fix(seeds)) && ...
        isnumeric(point) && isreal(point) && isscalar(point) && isfinite(point) && ...
        point>=1 && point<=flintmax && point==fix(point);
end
for name=["SelectedRank","SelectedPMI","SelectedPMIComponentsJSON","SelectedMatrixSHA256", ...
        "SelectedObjective_bpsHz","BestReportedRankObjective_bpsHz","BestJointObjective_bpsHz", ...
        "ConditionalPMIRegret_bpsHz","RankRegret_bpsHz","JointRegret_bpsHz", ...
        "SupportCount","CandidateCount","CandidateDomainSHA256","ChannelSHA256", ...
        "PortToPhysicalMatrixSHA256","SelectedWithinJointTie","SelectedWithinReportedRankTie", ...
        "JointTieCount","ReportedRankTieCount","ReferencePlane","Scope","ObjectiveClassification"]
    out.(name)=summary.(name);
    field="CSISelectionQuality"+name;
    assert(ismember(field,string(row.Properties.VariableNames)) && localEqual(row.(field),summary.(name),true), ...
        'sixgr:report:CSISelectionArchiveBinding','Published %s differs from original archive.',field);
end
for name=["RI","PMI"]
    expected=p.Inputs.Selection.(name);
    assert(ismember(name,string(row.Properties.VariableNames)) && localEqual(row.(name),expected,false), ...
        'sixgr:report:CSISelectionArchiveIdentity','The actual recommendation %s differs.',name);
end
out.Objective=string(p.Inputs.Policy.Objective); out.Receiver=string(p.Inputs.Policy.Receiver);
out.PowerNormalization=string(p.Inputs.Policy.PowerNormalization);
out.PhysicalPowerUnit=string(p.Inputs.Policy.PhysicalPowerUnit);
out.PhysicalPowerReferencePlane=string(p.Inputs.Policy.PhysicalPowerReferencePlane);
for name=["PowerNormalization","PhysicalPowerUnit","PhysicalPowerReferencePlane"]
    field="CSISelectionQuality"+name;
    assert(ismember(field,string(row.Properties.VariableNames)) && localEqual(row.(field),out.(name),false), ...
        'sixgr:report:CSISelectionArchivePlane','Original published %s differs.',field);
end
for name=["StatisticallyQualified","ActualPDSCHPerformanceQualified","CQIBLERQualified","CRISelectionQualified"]
    field="CSISelectionQuality"+name;
    assert(ismember(field,string(row.Properties.VariableNames)) && localEqual(row.(field),false,false), ...
        'sixgr:report:CSISelectionArchiveBinding','Private nominal evidence cannot carry %s.',field);
end
out.NoiseReceiptSHA256=string(p.Inputs.Disturbance.NoiseReceiptSHA256);
out.MATFile=string(row.CSISelectionQualityMATFile); out.MATFileSHA256=string(row.CSISelectionQualityMATFileSHA256);
out.CandidatesCSV=string(row.CSISelectionQualityCandidatesCSV);
out.CandidatesCSVSHA256=string(row.CSISelectionQualityCandidatesCSVSHA256);
end

function localOwner(row,id,in)
names=string(row.Properties.VariableNames);
token=jsondecode(string(row.CSISelectionQualityIdentityJSON));
assert(isequaln(jsonencode(orderfields(token)),jsonencode(orderfields(id))) && ...
    isequaln(id,in.Reference.Identity) && isequaln(id,in.Selection.Identity) && ...
    isequaln(id,in.Disturbance.Identity) && ...
    string(id.RequestSHA256)==sixgr.util.sha256Hex(jsonencode(orderfields(in.Request))), ...
    'sixgr:report:CSISelectionArchiveIdentity','Identity must bind the original row and every operand, not just resealed files.');
for name=string(fieldnames(id)).'
    alias=name;
    switch name
        case "ObservationID", alias="CSISelectionQualityObservationID";
        case "MeasurementID", alias="CSIMeasurementID";
        case "MeasurementDigest", alias="CSIMeasurementDigest";
        case "ConfigurationEpoch", alias="CSIConfigurationEpoch";
        case "ReportConfigID", alias="CSIReportConfigID";
        case "SampleRateHz", alias="ObservationSampleRateHz";
        case "ObservationSHA256", alias="ReceiverObservationSHA256";
        case "MeasurementSlot", alias="Slot";
        case "ResourceOrdinal0", alias="CRI";
        case "RequestSHA256", continue;
    end
    assert(ismember(alias,names),'sixgr:report:CSISelectionArchiveIdentity','Missing source identity %s.',alias);
    actual=row.(alias);
    if name=="ResourceID", actual="CSI-RS-"+string(actual); end
    assert(localEqual(actual,id.(name),false),'sixgr:report:CSISelectionArchiveIdentity', ...
        'Wrong source %s; do not transplant another observation/point.',alias);
end
for name=["RunID","RunTag","RunFolder","ExecutionID","ConfigHash","ScenarioID", ...
        "Seed","RandomSeed","ChannelSeed","NoiseSeed","SweepPointIndex","ConfiguredSNR_dB"]
    if ~ismember(name,names), continue; end
    value=row.(name);
    if (isstring(value)||ischar(value)) && (ismissing(string(value))||strlength(string(value))==0), continue; end
    if isnumeric(value) && isscalar(value) && isnan(value), continue; end
    assert(isfield(id,name),'sixgr:report:CSISelectionArchiveIdentity','Supplied population %s must remain sealed.',name);
end
if isfield(in.Reference,'CSIObservationPopulationJSON')
    for name=["CSIObservationPopulationJSON","CSIObservationPopulationBindingJSON"]
        assert(ismember(name,names) && string(row.(name))==string(in.Reference.(name)), ...
            'sixgr:report:CSISelectionArchiveIdentity','Retain original queue and actual TX binding, not callback population.');
    end
    assert(sixgr.util.sha256Hex(char(row.CSIObservationPopulationJSON))==in.Reference.CSIObservationPopulationJSONSHA256, ...
        'sixgr:report:CSISelectionArchiveChecksum','Original population text changed.');
end
end

function localPlaneAndNoise(row,in)
r=in.Reference; d=in.Disturbance; p=in.Policy;
assert(isequaln(r.TXAmplitudeScale*r.RawPortToPhysicalMatrix,r.PortToPhysicalMatrix) && ...
    sixgr.phy.mimo.MatrixContract.digest(r.RawPortToPhysicalMatrix)==r.RawPortToPhysicalMatrixSHA256 && ...
    p.PhysicalPowerReferencePlane=="raw_native_grid_physical_chain_coefficient_power", ...
    'sixgr:report:CSISelectionArchivePlane','Retain exact executed amplitude/map and raw-grid plane.');
expected="normalized_grid_coefficient_squared_units";
if string(d.WaveformAmplitudeUnit)=="sqrt_mW", expected="mW_scaled_grid_coefficient_squared_units"; end
assert(any(string(d.WaveformAmplitudeUnit)==["sqrt_mW","normalized_complex_baseband"]) && ...
    string(p.PhysicalPowerUnit)==expected && ...
    sixgr.util.sha256Hex(jsonencode(d.NoiseReceipt))==string(d.NoiseReceiptSHA256), ...
    'sixgr:report:CSISelectionArchiveNoise','Original noise receipt/unit seal must agree.');
for name=["ReceiverID","ReceiverWindowID","ReceiverClockDomain","ReceiverClockEpoch", ...
        "ObservationStartSample","ObservationEndSampleExclusive","SampleRateHz"]
    assert(isfield(d.NoiseReceipt,name) && localEqual(d.NoiseReceipt.(name),r.Identity.(name),false), ...
        'sixgr:report:CSISelectionArchiveIdentity','Noise receipt has wrong %s.',name);
end
receipt=d.NoiseReceipt;
assert(isfield(receipt,'ValidatedNoiseRecord') && isfield(receipt,'NativeOFDM') && ...
    receipt.ValidatedNoiseRecord.InjectedSampleNoiseVariance==d.SampleNoiseVariance && ...
    receipt.ValidatedNoiseRecord.NoiseStreamSeed==d.NoiseStreamSeed && ...
    receipt.NativeOFDM.SampleToGridNoiseVarianceGain==d.SampleToGridNoiseVarianceGain && ...
    receipt.NativeOFDM.SampleRate==r.Identity.SampleRateHz, ...
    'sixgr:report:CSISelectionArchiveNoise','Use the original executed variance/seed/native transform, not receiver-estimated noise.');
% Source row is the independent archive-binding anchor; do not silently
% accept a changed receipt merely because its internal hashes were updated.
names=string(row.Properties.VariableNames);
for name=string(fieldnames(receipt.ValidatedNoiseRecord)).'
    if name=="ObservationID", continue; end
    assert(ismember(name,names) && localEqual(row.(name),receipt.ValidatedNoiseRecord.(name),true), ...
        'sixgr:report:CSISelectionArchiveNoise','Original source noise %s disagrees.',name);
end
end

function localCSV(actual,p)
expected=p.PublishedCandidates;
assert(istable(expected) && isequal(actual.Properties.VariableNames,expected.Properties.VariableNames) && ...
    height(actual)==height(p.Candidates) && height(actual)==height(expected), ...
    'sixgr:report:CSISelectionArchiveCSV','Retain every original candidate column and row.');
for name=string(expected.Properties.VariableNames)
    assert(localEqual(actual.(name),expected.(name),false), ...
        'sixgr:report:CSISelectionArchiveCSV','Candidate CSV differs at %s.',name);
end
T=p.Candidates;
for name=string(T.Properties.VariableNames)
    if iscell(T.(name)), continue; end
    assert(ismember(name,string(expected.Properties.VariableNames)) && localEqual(expected.(name),T.(name),false), ...
        'sixgr:report:CSISelectionArchiveCSV','Serialized candidate %s differs from its arithmetic.',name);
end
for rank=unique(T.Rank).'
    request=p.Inputs.Request; request.Rank=rank;
    legal=sixgr.phy.mimo.CodebookEngine.enumerate(request);
    for k=find(T.Rank==rank).'
        at=find(legal.CandidateIndices==T.PMI(k));
        assert(isscalar(at) && isequaln(p.CandidateMatrices{k},legal.Matrices(:,:,at)) && ...
            isequaln(sixgr.phy.mimo.MatrixContract.deserialize(actual.CandidateMatrixJSON(k)),p.CandidateMatrices{k}) && ...
            isequaln(localArray(actual.SupportObjectiveJSON(k)),T.SupportObjective_bpsHz{k}) && ...
            isequaln(localArray(actual.LayerSINRJSON(k)),T.LayerSINR{k}), ...
            'sixgr:report:CSISelectionArchiveCSV','Original legal matrix/per-support/per-layer operands differ.');
    end
end
for name=string(fieldnames(p.Identity)).'
    value=p.Identity.(name); if ischar(value), value=string(value); end
    assert(ismember(name,string(actual.Properties.VariableNames)) && ...
        localEqual(actual.(name),repmat(value,height(actual),1),false), ...
        'sixgr:report:CSISelectionArchiveIdentity','Candidate %s population differs.',name);
end
assert(all(string(actual.IdentitySHA256)==p.IdentitySHA256) && ...
    all(string(actual.OperandSetSHA256)==p.OperandSetSHA256) && ...
    all(string(actual.SupportJSON)==string(actual.SupportJSON(1))) && ...
    isequaln(localArray(actual.SupportJSON(1)),p.Inputs.Reference.Support), ...
    'sixgr:report:CSISelectionArchiveIdentity','Candidate source/support seal differs.');
for name=["ReferencePlane","Scope","ObjectiveClassification","CandidateDomainSHA256", ...
        "ChannelSHA256","PortToPhysicalMatrixSHA256"]
    assert(all(string(actual.(name))==string(p.Summary.(name))), ...
        'sixgr:report:CSISelectionArchivePlane','Candidate %s scope differs.',name);
end
for name=["PhysicalPowerReferencePlane","PhysicalPowerUnit","PowerNormalization"]
    assert(all(string(actual.(name))==string(p.Inputs.Policy.(name))), ...
        'sixgr:report:CSISelectionArchivePlane','Candidate %s units differ.',name);
end
assert(all(string(actual.CSISelectionQualityObservationID)==string(p.Identity.ObservationID)) && ...
    all(sixgr.truth.numericMeasurementColumn(actual.StatisticallyQualified,'StatisticallyQualified')==0) && ...
    all(string(actual.EvidenceRole)=="private_UE_selection_quality_not_UCI_delivery_or_applied_grant"), ...
    'sixgr:report:CSISelectionArchiveBinding','Candidate rows cannot assert accuracy/delivery qualification.');
end

function value=localArray(token)
p=jsondecode(token);
assert(string(p.Contract)=="sixgr_real_array_column_major/v1" && any(string(p.Class)==["double","single"]), ...
    'sixgr:report:CSISelectionArchiveCSV','Unknown retained array representation.');
value=reshape(cast(p.ColumnMajorValues,char(p.Class)),double(p.Shape(:).'));
assert(localDigest(value)==string(p.SHA256),'sixgr:report:CSISelectionArchiveChecksum','Array bytes/shape differ.');
end

function equal=localEqual(actual,expected,roundedSource)
if isnumeric(expected)||islogical(expected)
    actual=sixgr.truth.numericMeasurementColumn(actual,'CSISelectionEvidence');
    expected=double(expected); equal=isequaln(actual,expected);
    if ~equal && roundedSource && isequal(size(actual),size(expected)) && all(isfinite(actual),'all') && all(isfinite(expected),'all')
        equal=all(abs(actual-expected)<=256*eps(max(abs(actual),abs(expected))),'all');
    end
else
    equal=isequaln(string(actual),string(expected));
end
end

function path=localPath(root,relative,kind)
relative=replace(string(relative),'\','/');
assert(isscalar(relative) && ~ismissing(relative) && ...
    ~isempty(regexp(char(relative),char("^beamforming/"+kind+"/csi_selection_quality_[0-9a-f]{64}\."+kind+"$"),'once')), ...
    'sixgr:report:CSISelectionArchivePath','Use the exact run-relative original archive path.');
path=string(java.io.File(char(fullfile(root,relative))).getCanonicalPath());
assert(startsWith(path,root+filesep,'IgnoreCase',ispc) && isfile(path), ...
    'sixgr:report:CSISelectionArchiveMissing','Missing declared archive within supplied artifact container.');
end

function localFileHash(path,hash)
hash=string(hash);
assert(isscalar(hash) && ~ismissing(hash) && ~isempty(regexp(char(hash),'^[0-9a-f]{64}$','once')) && ...
    string(sixgr.util.sha256File(path))==hash, ...
    'sixgr:report:CSISelectionArchiveChecksum','Original artifact bytes changed.');
end

function hash=localDigest(value)
hash=sixgr.truth.csiSelectionArchiveDigest(value);
end

