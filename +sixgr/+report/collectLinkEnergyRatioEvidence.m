function observations = collectLinkEnergyRatioEvidence(trials,direction,source,sourceSHA256)
%COLLECTLINKENERGYRATIOEVIDENCE Explicit branch-mean SCH energy arithmetic.
% Diagnostic, one row per source row, never independent-trial/coverage proof.
% Configured reference Es, effective impairment variance, post-EQ SINR and
% target code rate are NOT operands. Generic Es/N0 remains unavailable.
arguments
    trials table
    direction (1,1) string
    source (1,1) string
    sourceSHA256 (1,1) string = ""
end
p=prototype(); observations=struct2table(p,'AsArray',true); observations=observations([],:);
for k=1:height(trials)
    row=trials(k,:); r=p; r.Direction=direction; r.SourceArtifact=source;
    r.SourceArtifactSHA256=sourceSHA256; r.SourceRow=k; r.InputIdentityJSON=identityJSON(row);
    r.Modulation=textAt(row,"Modulation");
    [r.ModulationOrderQm,r.CanonicalModulation]=sixgr.report.reportModulationOrder(r.Modulation);
    r.LinkEnergyEvidenceJSON=textAt(row,"LinkEnergyEvidenceJSON");
    r.LinkEnergyEvidenceSHA256=textAt(row,"LinkEnergyEvidenceSHA256");
    r.EvidenceID=string(sixgr.util.sha256Hex(jsonencode(struct('Direction',direction, ...
        'Source',source,'SHA256',sourceSHA256,'SourceRow',k,'Identity',r.InputIdentityJSON, ...
        'EnergyEvidenceSHA256',r.LinkEnergyEvidenceSHA256))));
    if strlength(r.LinkEnergyEvidenceJSON)==0
        require(strlength(r.LinkEnergyEvidenceSHA256)==0,'A digest without an original receipt is invalid.');
        observations=[observations;struct2table(r,'AsArray',true)]; %#ok<AGROW>
        continue;
    end
    require(validHash(r.LinkEnergyEvidenceSHA256) && strcmpi(r.LinkEnergyEvidenceSHA256, ...
        sixgr.util.sha256Hex(char(r.LinkEnergyEvidenceJSON))),'Energy receipt JSON digest mismatch.');
    try, e=jsondecode(r.LinkEnergyEvidenceJSON);
    catch cause, error('sixgr:report:InvalidEnergyEvidence','Invalid energy JSON: %s',cause.message); end
    require(isstruct(e) && isscalar(e) && all(isfield(e,["Version","Source","Identity","Available","Status"])) && ...
        string(e.Version)=="branch_mean_sch_energy/v1" && string(e.Source)=="sixgr.link.captureLinkEnergyEvidence", ...
        'Unsupported energy receipt contract/source.');
    require(isstruct(e.Identity) && isscalar(e.Identity) && isfield(e.Identity,'Direction') && ...
        string(e.Identity.Direction)==direction,'Direction must match the original energy owner.');
    missingNumeric=missingNumericIdentityFields(e);
    for name=string(fieldnames(e.Identity))'
        require(ismember(name,string(row.Properties.VariableNames)),"Original energy identity missing: "+name);
        actual=row.(name); if iscell(actual) && isscalar(actual), actual=actual{1}; end
        original=e.Identity.(name);
        if ismember(name,missingNumeric)
            require(isstruct(original) && isscalar(original) && ...
                isequal(sort(string(fieldnames(original))),sort(["ValueState";"OriginalClass";"OriginalSize"])) && ...
                (ischar(original.ValueState)||isstring(original.ValueState)) && ...
                isscalar(string(original.ValueState)) && string(original.ValueState)=="original_numeric_scalar_NaN" && ...
                (ischar(original.OriginalClass)||isstring(original.OriginalClass)) && ...
                isscalar(string(original.OriginalClass)) && any(string(original.OriginalClass)==["double","single"]) && ...
                isnumeric(original.OriginalSize) && isequal(double(original.OriginalSize(:)),[1;1]) && ...
                isnumeric(actual) && isreal(actual) && isscalar(actual) && isnan(actual), ...
                "Explicit unavailable numeric identity must match the original scalar NaN: "+name);
        else
            require(validPresentIdentity(original) && sameValue(actual,original), ...
                "Original energy identity mismatch: "+name);
        end
    end
    require(islogical(e.Available) && isscalar(e.Available),'Availability must be explicitly logical.');
    r.Status=string(e.Status);
    if ~e.Available
        observations=[observations;struct2table(r,'AsArray',true)]; %#ok<AGROW>
        continue;
    end
    needed=["ReferencePlane","WaveformAmplitudeUnit","MeasurementReceipt","NoiseReceipt", ...
        "DataIndicesSHA256","UniqueTFSupportSHA256","GridSize","EnergySumPerReceiveBranch","UniqueTimeFrequencyRECount", ...
        "Modulation","CanonicalModulation","ModulationOrderQm","ModulationSymbolCount", ...
        "CodedBitCount","TransportBlockBitCount","RateMatchAccountingJSON", ...
        "DesiredWaveformSHA256","TransmittedWaveformSHA256","DataSymbolsSHA256","TransportBlockSHA256","NumLayers"];
    require(all(isfield(e,needed)),'Available evidence must retain all original operands.');
    require(string(e.ReferencePlane)==p.ReferencePlane && ...
        any(string(e.WaveformAmplitudeUnit)==["sqrt_mW","normalized_complex_baseband"]), ...
        'Only the explicitly declared pre-noise/pre-RX-RF native grid plane is supported.');
    for name=["DesiredWaveformSHA256","TransmittedWaveformSHA256","DataSymbolsSHA256","TransportBlockSHA256", ...
            "DataIndicesSHA256","UniqueTFSupportSHA256"]
        require(validHash(string(e.(name))),"Invalid original operand digest: "+name);
    end
    m=e.MeasurementReceipt; n=e.NoiseReceipt;
    require(isstruct(m) && isscalar(m) && all(isfield(m,["Version","Source","MeasurementPlane", ...
        "SignalEnergyPerOccupiedRE","TransmitterIndexCount","UniqueTimeFrequencyRECount", ...
        "ReceiveBranchCount","ObservationCount","SignalFamily","ConfiguredCyclicPrefix", ...
        "ConfiguredSubcarrierSpacing_kHz","EnergySumPerReceiveBranch","GridSize", ...
        "DataIndicesSHA256","UniqueTFSupportSHA256","ReferenceWaveformSHA256","ReceiptReduction"])) && ...
        string(m.Version)=="sixgr.phy.waveform.received_occupied_re_energy/v1" && ...
        string(m.Source)=="sixgr.phy.waveform.measureReceivedOccupiedREEnergy" && ...
        string(m.MeasurementPlane)=="noiseless_received_resource_grid_post_channel_post_large_scale_pre_noise", ...
        'Original noiseless received-energy measurement is required.');
    family="PDSCH"; if direction=="UL", family="PUSCH"; end
    require(string(m.SignalFamily)==family,'Energy must belong to the original SCH direction.');
    % Validate the original JSON operands before double/reshape/concatenation.
    % Otherwise a resealed text field can become its numeric character codes
    % and even satisfy a coherently changed arithmetic closure.
    for value={e.GridSize,m.GridSize}
        require(realNumericVector(value{1}) && numel(value{1})==2 && ints(value{1}), ...
            'Original grid dimensions must be a two-element numeric vector.');
    end
    for value={e.EnergySumPerReceiveBranch,m.EnergySumPerReceiveBranch}
        require(realNumericVector(value{1}) && all(value{1}(:)>=0), ...
            'Original branch energies must be a finite nonnegative numeric vector.');
    end
    for name=["UniqueTimeFrequencyRECount","ModulationOrderQm","ModulationSymbolCount", ...
            "CodedBitCount","TransportBlockBitCount","NumLayers"]
        require(realNumericScalar(e.(name)) && ints(e.(name)), ...
            "Original energy count must be a positive numeric integer: "+name);
    end
    for name=["TransmitterIndexCount","UniqueTimeFrequencyRECount","ReceiveBranchCount","ObservationCount"]
        require(realNumericScalar(m.(name)) && ints(m.(name)), ...
            "Original measurement count must be a positive numeric integer: "+name);
    end
    require(realNumericScalar(m.SignalEnergyPerOccupiedRE) && m.SignalEnergyPerOccupiedRE>=0, ...
        'Original measured mean energy must be a finite nonnegative numeric scalar.');
    validateNoise(n,m);
    gridSize=double(e.GridSize(:)); count=double(e.UniqueTimeFrequencyRECount);
    energy=double(e.EnergySumPerReceiveBranch(:)); branches=double(m.ReceiveBranchCount);
    require(numel(gridSize)==2 && ints(gridSize) && isequal(gridSize,double(m.GridSize(:))) && ...
        isscalar(count) && ints(count) && count<=prod(gridSize) && isscalar(branches) && ints(branches), ...
        'Exact grid/support/receive-branch dimensions are required.');
    require(string(m.ReceiptReduction)=="exact_per_branch_sum_and_count_on_original_unique_TF_support" && ...
        string(m.DataIndicesSHA256)==string(e.DataIndicesSHA256) && ...
        string(m.UniqueTFSupportSHA256)==string(e.UniqueTFSupportSHA256) && ...
        string(m.ReferenceWaveformSHA256)==string(e.DesiredWaveformSHA256) && ...
        numel(energy)==branches && isequal(energy,double(m.EnergySumPerReceiveBranch(:))) && ...
        m.ObservationCount==count*branches && m.UniqueTimeFrequencyRECount==count && ...
        isscalar(m.TransmitterIndexCount) && ints(m.TransmitterIndexCount) && m.TransmitterIndexCount>=count, ...
        'Original compact sums, support identities and counts must close exactly.');
    require(all(isfinite(energy) & energy>=0),'Retained branch sums must be finite and nonnegative.');
    meanEnergy=sum(energy)/(count*branches);
    % Per-branch versus flattened summation may round differently. Bound
    % that reduction error, never replace the original measured mean.
    require(isnumeric(m.SignalEnergyPerOccupiedRE) && isscalar(m.SignalEnergyPerOccupiedRE) && ...
        isfinite(m.SignalEnergyPerOccupiedRE) && abs(meanEnergy-double(m.SignalEnergyPerOccupiedRE))<= ...
        16*eps(max([abs(meanEnergy),abs(double(m.SignalEnergyPerOccupiedRE)),realmin]))*max(1,count), ...
        'Original measurement mean disagrees with retained energy sums.');
    [qm,canonical]=sixgr.report.reportModulationOrder(string(e.Modulation));
    require(isscalar(qm) && isfinite(qm) && qm==e.ModulationOrderQm && ...
        canonical==string(e.CanonicalModulation),'Modulation Qm must match the canonical catalog.');
    require(ints(e.CodedBitCount) && isscalar(e.CodedBitCount) && ...
        ints(e.TransportBlockBitCount) && isscalar(e.TransportBlockBitCount) && ...
        ints(e.ModulationSymbolCount) && isscalar(e.ModulationSymbolCount) && ...
        e.CodedBitCount==qm*e.ModulationSymbolCount,'Exact SCH bit/symbol counts must close.');
    require(ints(e.NumLayers) && isscalar(e.NumLayers) && e.NumLayers<=4 && ...
        e.ModulationSymbolCount==count*e.NumLayers,'Single-CW layer support must match the exact symbol count.');
    coding=table("LDPCSelectionAccounting/v2",string(e.RateMatchAccountingJSON),double(e.CodedBitCount), ...
        'VariableNames',{'CodingAccountingVersion','RateMatchAccountingJSON','RateMatchedBits'});
    [a,~]=sixgr.report.collectLDPCRateMatchEvidence(coding,direction,source,sourceSHA256);
    require(a.NumCodewords==1 && a.SelectedPositions==e.CodedBitCount,'Only original single-CW SCH selections are supported.');
    checkScalar(row,"RateMatchedBits",e.CodedBitCount);
    checkScalar(row,"TBSize_bits",e.TransportBlockBitCount);
    checkScalar(row,"ModulationOrderQm",qm);
    if strlength(r.Modulation)>0
        require(isfinite(r.ModulationOrderQm) && r.ModulationOrderQm==qm,'Trial modulation contradicts the original energy record.');
    end
    r.Modulation=string(e.Modulation); r.CanonicalModulation=canonical; r.ModulationOrderQm=qm;
    r.WaveformAmplitudeUnit=string(e.WaveformAmplitudeUnit);
    r.EnergyUnit="normalized_native_grid_coefficient_squared_units";
    if r.WaveformAmplitudeUnit=="sqrt_mW", r.EnergyUnit="mW_scaled_native_grid_coefficient_squared_units"; end
    r.ReceiveBranchCount=branches; r.UniqueTimeFrequencyRECount=count;
    r.ObservationCount=count*branches; r.MeanRxBranchOccupiedREEnergy=meanEnergy;
    r.MeanRxBranchSCHSupportEnergy=sum(energy)/branches;
    r.PureGridNoiseVariance=double(n.GridNoiseVariance);
    r.CodedBitCount=double(e.CodedBitCount); r.TransportBlockBitCount=double(e.TransportBlockBitCount);
    r.ModulationSymbolCount=double(e.ModulationSymbolCount);
    r.ActualTransportBlockRate=r.TransportBlockBitCount/r.CodedBitCount;
    if meanEnergy==0
        r.Status="not_available_zero_reference_energy";
    elseif r.PureGridNoiseVariance==0
        r.Status="not_available_zero_noise_variance";
    else
        % Log-domain ratios avoid overflow/underflow without clipping zero
        % energy/noise into invented finite measurements.
        r.MeanRxBranchOccupiedREToN0_dB=10*(log10(meanEnergy)-log10(r.PureGridNoiseVariance));
        r.MeanRxBranchEcN0_dB=10*(log10(r.MeanRxBranchSCHSupportEnergy)-log10(r.CodedBitCount)-log10(r.PureGridNoiseVariance));
        r.MeanRxBranchEbN0_dB=10*(log10(r.MeanRxBranchSCHSupportEnergy)-log10(r.TransportBlockBitCount)-log10(r.PureGridNoiseVariance));
        r.RatioAvailable=true; r.Status="branch_mean_SCH_energy_arithmetic_verified_not_execution_qualification";
    end
    observations=[observations;struct2table(r,'AsArray',true)]; %#ok<AGROW>
end
end

function validateNoise(n,m)
required=["Version","Source","NoiseKind","SNRReferencePlane","ComplexVarianceDefinition", ...
    "GridNoiseVariance","SampleNoiseVariance","SampleToGridNoiseVarianceGain", ...
    "SignalEnergyPerOccupiedRE","RequestedEsN0_dB","NumRxColumns", ...
    "ConfiguredCyclicPrefix","ConfiguredSubcarrierSpacing_kHz"];
require(isstruct(n) && isscalar(n) && all(isfield(n,required)) && ...
    string(n.Version)=="sixgr.phy.waveform.occupied_re_awgn/v1" && ...
    string(n.Source)=="sixgr.phy.waveform.addOccupiedREAWGN" && ...
    string(n.NoiseKind)=="independent_zero_mean_circular_complex_time_domain_awgn" && ...
    string(n.SNRReferencePlane)=="occupied_resource_grid_re_pre_equalization" && ...
    string(n.ComplexVarianceDefinition)=="E[abs(n)^2]", ...
    'N0 requires the original pure-AWGN receipt, not effective noise-plus-interference variance.');
for record={m,n}
    value=record{1};
    require(all(isfield(value,["ApproximationMode","ProxyUsed","FallbackUsed"])) && ...
        string(value.ApproximationMode)=="none" && isequal(value.ProxyUsed,false) && isequal(value.FallbackUsed,false), ...
        'Approximate/proxy/fallback evidence cannot qualify the native energy arithmetic contract.');
    require(realNumericScalar(value.ConfiguredSubcarrierSpacing_kHz) && ...
        value.ConfiguredSubcarrierSpacing_kHz>0, ...
        'Original operator SCS must be a positive numeric scalar.');
end
require(realNumericScalar(n.NumRxColumns) && ints(n.NumRxColumns), ...
    'Original noise branch count must be a positive numeric integer.');
for name=["GridNoiseVariance","SampleNoiseVariance","SampleToGridNoiseVarianceGain", ...
        "SignalEnergyPerOccupiedRE","RequestedEsN0_dB"]
    require(realNumericScalar(n.(name)),"Original noise operand must be a finite numeric scalar: "+name);
end
require(n.NumRxColumns==m.ReceiveBranchCount && ...
    string(n.ConfiguredCyclicPrefix)==string(m.ConfiguredCyclicPrefix) && ...
    n.ConfiguredSubcarrierSpacing_kHz==m.ConfiguredSubcarrierSpacing_kHz, ...
    'Original noise and energy operator/branch identities must match.');
values=[n.GridNoiseVariance,n.SampleNoiseVariance,n.SampleToGridNoiseVarianceGain, ...
    n.SignalEnergyPerOccupiedRE,n.RequestedEsN0_dB];
require(isnumeric(values) && isreal(values) && numel(values)==5 && all(isfinite(values)) && ...
    values(1)>=0 && values(2)>=0 && values(3)>0 && values(4)>0, 'Invalid original noise operands.');
require(near(values(1),values(2)*values(3)) && near(values(1),values(4)*10^(-values(5)/10)), ...
    'Original sample/grid variance and configured calibration equation must close.');
end

function p=prototype()
p=struct('Direction',"",'SourceArtifact',"",'SourceArtifactSHA256',"",'SourceRow',NaN, ...
    'EvidenceID',"",'InputIdentityJSON',"",'LinkEnergyEvidenceJSON',"",'LinkEnergyEvidenceSHA256',"", ...
    'Modulation',"",'CanonicalModulation',"",'ModulationOrderQm',NaN, ...
    'RatioAvailable',false,'CountsTowardCoverage',false,'Status',"not_available_original_energy_receipt_not_retained", ...
    'ReferencePlane',"noiseless_desired_received_grid_on_SCH_data_support_pre_noise_pre_RX_front_end", ...
    'Scope',"branch_mean_per_attempt_not_per_layer_Es_not_normative_NR_EcNo_not_combined_HARQ", ...
    'WaveformAmplitudeUnit',"",'EnergyUnit',"",'ReceiveBranchCount',NaN, ...
    'UniqueTimeFrequencyRECount',NaN,'ObservationCount',NaN,'ModulationSymbolCount',NaN, ...
    'MeanRxBranchOccupiedREEnergy',NaN,'MeanRxBranchSCHSupportEnergy',NaN, ...
    'PureGridNoiseVariance',NaN,'CodedBitCount',NaN,'TransportBlockBitCount',NaN, ...
    'ActualTransportBlockRate',NaN,'MeanRxBranchOccupiedREToN0_dB',NaN, ...
    'MeanRxBranchEcN0_dB',NaN,'MeanRxBranchEbN0_dB',NaN, ...
    'EsN0_dB',NaN,'EcNo_dB',NaN,'EbNo_dB',NaN);
end

function require(tf,message)
assert(isscalar(tf) && tf,'sixgr:report:InvalidEnergyEvidence','%s',message);
end
function tf=ints(x)
tf=isnumeric(x) && isreal(x) && ~isempty(x) && all(isfinite(x(:)) & x(:)>0 & ...
    x(:)==fix(x(:)) & x(:)<=flintmax);
end
function tf=realNumericScalar(x)
tf=isnumeric(x) && isreal(x) && isscalar(x) && isfinite(x);
end
function tf=realNumericVector(x)
tf=isnumeric(x) && isreal(x) && isvector(x) && ~isempty(x) && all(isfinite(x(:)));
end
function tf=near(a,b)
tf=isnumeric(a) && isnumeric(b) && isscalar(a) && isscalar(b) && isfinite(a) && isfinite(b) && ...
    abs(a-b)<=64*eps(max([abs(double(a)),abs(double(b)),realmin]));
end
function tf=validHash(value)
tf=isscalar(value) && ~ismissing(value) && ~isempty(regexp(char(value),'^[0-9A-Fa-f]{64}$','once'));
end
function names=missingNumericIdentityFields(e)
names=strings(0,1);
hasContract=isfield(e,'IdentityValueContract');
hasFields=isfield(e,'IdentityMissingNumericFields');
require(hasContract==hasFields,'Explicit unavailable identity needs both its contract and field list.');
if ~hasContract, return; end % Original finite-only v1 receipts remain valid.
require((ischar(e.IdentityValueContract)||isstring(e.IdentityValueContract)) && ...
    isscalar(string(e.IdentityValueContract)) && ...
    string(e.IdentityValueContract)=="scalar_identity_with_explicit_numeric_NaN/v1", ...
    'Unsupported original identity value contract.');
raw=e.IdentityMissingNumericFields;
if isnumeric(raw) && isempty(raw) && isequal(size(raw),[0 0]), return; end
require(ischar(raw)||isstring(raw)||iscellstr(raw), ...
    'Unavailable identity fields must be explicit names, never numeric values.');
names=string(raw(:));
if ischar(raw), names=string(raw); end
require(isvector(names) && ~isempty(names) && all(~ismissing(names) & strlength(names)>0) && ...
    numel(unique(names))==numel(names) && all(isfield(e.Identity,names)), ...
    'Unavailable identity declarations must be unique original field names.');
names=names(:);
end
function tf=validPresentIdentity(value)
tf=false;
if isnumeric(value), tf=isreal(value) && isscalar(value) && isfinite(value);
elseif islogical(value), tf=isscalar(value);
elseif ischar(value)||isstring(value)
    tf=(isstring(value)||isrow(value)||isempty(value)) && ...
        isscalar(string(value)) && ~ismissing(string(value));
end
end
function tf=sameValue(a,b)
if iscell(a) && isscalar(a), a=a{1}; end
if (ischar(a)||isstring(a)) && (ischar(b)||isstring(b))
    tf=isequal(string(a),string(b));
elseif isnumeric(a) && isnumeric(b), tf=isequaln(double(a(:)),double(b(:)));
else, tf=isequaln(a,b); end
end
function checkScalar(row,name,expected)
if ~ismember(name,string(row.Properties.VariableNames)), return; end
value=row.(name); if iscell(value) && isscalar(value), value=value{1}; end
if isnumeric(value) && isscalar(value) && isnan(value), return; end
require(isnumeric(value) && isscalar(value) && double(value)==double(expected),"Trial count mismatch: "+name);
end
function value=textAt(row,name)
value=""; if ~ismember(name,string(row.Properties.VariableNames)), return; end
raw=row.(name); if iscell(raw) && isscalar(raw), raw=raw{1}; end
if ~(ischar(raw)||isstring(raw)), return; end
raw=string(raw); if isscalar(raw) && ~ismissing(raw), value=raw; end
end
function token=identityJSON(row)
names=string(row.Properties.VariableNames);
keep=ismember(names,["Direction","ExecutionID","RunID","RunTag","RunFolder","ScenarioID","ConfigHash", ...
    "Seed","RandomSeed","ChannelSeed","UEIndex","UEID","RNTI","ServingCell","CellID","Frame","Slot", ...
    "LogicalTBID","TransmissionAttemptID","HARQProcess","RV","NDI","ReceiverObservationSHA256", ...
    "ObservationStartSample","ObservationEndSampleExclusive","ObservationSampleRateHz", ...
    "ReceiverClockDomain","ReceiverClockEpoch","ReceiverID","ExecutionBackend","ApproximationMode"]) | ...
    startsWith(names,"Sweep") | startsWith(names,"Point") | startsWith(names,"Population") | names=="ConfiguredSNR_dB";
identity=struct();
for name=names(keep)
    value=row.(name);
    % CSV text imports may use scalar string or a scalar cell containing
    % char. They denote the same original value, not different populations.
    % Remove only that container; never flatten a vector or trim its text.
    if iscell(value)
        require(isscalar(value),"Identity must contain one scalar value: "+name);
        value=value{1};
    end
    if ischar(value)
        require(isrow(value)||isempty(value),"Identity text must be scalar: "+name);
        value=string(value);
    elseif isstring(value)
        require(isscalar(value),"Identity text must be scalar: "+name);
    else
        require((isnumeric(value)||islogical(value)) && isreal(value) && isscalar(value), ...
            "Identity must contain one scalar numeric, logical or text value: "+name);
    end
    identity.(name)=value;
end
token=string(jsonencode(identity));
end
