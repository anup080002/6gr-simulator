function row=exportCSIRSReceivedEVMPairs(root,row)
% Dedicated received-aggregate CSV, independently read from immutable pairs.
if ~ismember('CSIRSReceivedEVMSamplesCount',row.Properties.VariableNames)|| ...
        row.CSIRSReceivedEVMSamplesCount==0||~sixgr.util.persistenceEnabled(), return; end
bound=row;
names=string(row.Properties.VariableNames);
for field=names(startsWith(names,"CSIRSReceivedEVMSamples"))
    bound.(replace(field,"CSIRSReceivedEVMSamples","ControlEVMSamples"))=row.(field);
end
pairs=sixgr.report.readControlEVMPairs(bound,fullfile(root,'air_interface','csv','csi_rs_trials.csv'));
token=string(row.CSIRSReceivedEVMIsolationEvidenceJSON);
assert(sixgr.util.sha256Hex(char(token))==row.CSIRSReceivedEVMIsolationEvidenceSHA256, ...
    'sixgr:report:CSIRSReceivedEVMProof','The retained original isolation receipt changed.');
proof=jsondecode(token);
assert(islogical(proof.Available)&&isscalar(proof.Available)&&proof.Available&& ...
    string(proof.ContractVersion)=="sixgr.truth.EmittedComponentIsolation/v1"&& ...
    string(proof.Source)=="original_successful_execution_finite_signal_dependency", ...
    'sixgr:report:CSIRSReceivedEVMProof','The receipt must be the original executed isolation proof.');
rows=cell(numel(pairs),1); errorEnergy=0; referenceEnergy=0;
for k=1:numel(pairs)
    p=pairs(k);
    assert(islogical(p.IsolatedComponentProved)&&isscalar(p.IsolatedComponentProved)&& ...
        p.IsolatedComponentProved&&isequal(p.GainOrPhaseFitted,false)&& ...
        isequal(p.ReceiverUsesScoringReference,false)&& ...
        string(p.ReferenceSource)=="same_execution_isolated_emitted_aggregate_CSI_pre_RX_grid"&& ...
        string(p.IsolationEvidenceSHA256)==row.CSIRSReceivedEVMIsolationEvidenceSHA256, ...
        'sixgr:report:CSIRSReceivedEVMProof','Use original hash-bound received aggregate pairs.');
    y=complex(p.MeasuredReal(:),p.MeasuredImag(:)); d=complex(p.ReferenceReal(:),p.ReferenceImag(:));
    n=numel(d); assert(numel(y)==n&&numel(p.SampleIndex)==n&&all(isfinite([y;d])));
    ee=abs(y-d).^2; rr=abs(d).^2;
    errorEnergy=errorEnergy+sum(ee); referenceEnergy=referenceEnergy+sum(rr);
    rows{k}=table(repmat(string(p.ObservationID),n,1),repmat(p.PortIndex,n,1), ...
        p.SampleIndex(:),real(d),imag(d),real(y),imag(y),ee,rr, ...
        repmat(string(p.ReferencePlane),n,1),repmat(string(p.ReferenceSource),n,1), ...
        false(n,1),false(n,1),false(n,1),false(n,1),false(n,1), ...
        'VariableNames',{'ObservationID','ReceiveElementIndex0', ...
        'PhysicalGridIndex0','ReferenceReal','ReferenceImag','MeasuredReal','MeasuredImag', ...
        'ErrorEnergy','ReferenceEnergy','ReferencePlane','ReferenceSource', ...
        'RFConformanceQualified','StandardizedAccuracyQualified','PowerUnitQualified', ...
        'StandardizedReferencePointQualified','HardwareQualified'});
end
T=vertcat(rows{:});
assert(height(T)==row.CSIRSReceivedEVMSampleCount&& ...
    abs(errorEnergy-row.CSIRSReceivedEVMErrorEnergy)<=128*eps(max(1,errorEnergy))&& ...
    abs(referenceEnergy-row.CSIRSReceivedEVMReferenceEnergy)<=128*eps(max(1,referenceEnergy)), ...
    'sixgr:report:CSIRSReceivedEVMClosure','Stored received pairs must close the original producer energies and count.');
relative="air_interface/csv/csi_received_evm/"+row.CSIRSReceivedEVMSamplesContentSHA256+".csv";
target=fullfile(root,relative);
sixgr.util.csvWriteTable(target,T,'PreserveSchema',true);
row.CSIRSReceivedEVMPairsCSV=relative;
row.CSIRSReceivedEVMPairsCSVSHA256=sixgr.util.sha256File(target);
end
