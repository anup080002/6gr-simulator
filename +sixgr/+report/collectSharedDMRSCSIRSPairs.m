function pairs=collectSharedDMRSCSIRSPairs(root,trials)
% Recompute the retained common-plane operands, not a difference of means.
pairs=table();
if isempty(trials) || ~ismember('DMRSCSIRSComparisonMATFile',trials.Properties.VariableNames), return; end
for n=1:height(trials)
    row=trials(n,:); path=string(row.DMRSCSIRSComparisonMATFile);
    if ismissing(path) || strlength(path)==0, continue; end
    required={'DMRSCSIRSComparisonMATFileSHA256','DMRSCSIRSComparisonCSV', ...
        'DMRSCSIRSComparisonCSVSHA256','DMRSCSIRSComparisonObservationID'};
    assert(all(ismember(required,row.Properties.VariableNames)), ...
        'sixgr:report:PairedChannelArchiveBinding','An archive declaration needs its complete source binding.');
    matPath=localPath(root,path); csvPath=localPath(root,string(row.DMRSCSIRSComparisonCSV));
    assert(isfile(matPath) && isfile(csvPath) && ...
        string(sixgr.phy.waveform.WaveformHash.file(matPath))==string(row.DMRSCSIRSComparisonMATFileSHA256) && ...
        string(sixgr.phy.waveform.WaveformHash.file(csvPath))==string(row.DMRSCSIRSComparisonCSVSHA256), ...
        'sixgr:report:PairedChannelArchiveChecksum','Missing or corrupt declared source is not a valid measurement.');
    a=load(matPath); resources=sixgr.util.csvReadTable(csvPath,'TextType','string');
    assert(any(a.Contract==["same_execution_paired_DMRS_CSI_RS_archive/v1", ...
        "same_execution_paired_DMRS_CSI_RS_archive/v2"]) && ...
        a.ObservationID==string(row.DMRSCSIRSComparisonObservationID) && ...
        a.ResourcesCSVSHA256==string(row.DMRSCSIRSComparisonCSVSHA256) && isequaln(a.Resources,resources) && ...
        ~a.ReferenceUsedByReceiver && ~a.StatisticallyQualified, ...
        'sixgr:report:PairedChannelArchiveBinding','Retained source/CSV/contract must match exactly.');
    values=table2array(removevars(a.Resources,'DMRSCSIRSComparisonObservationID'));
    token=sixgr.phy.waveform.WaveformHash.bytes(string(jsonencode(a.Identity))+"|"+ ...
        sixgr.phy.waveform.WaveformHash.runtimeArray(values));
    assert(a.ObservationID=="paired_dmrs_csirs_"+string(token) && isfield(a.Identity,'Population'), ...
        'sixgr:report:PairedChannelArchiveBinding','The immutable observation includes original population and values.');
    population=a.Identity.Population;
    ptoken=string(population.PreparedDataPopulationJSON);
    if strlength(ptoken)>0
        assert(ptoken==string(jsonencode(sixgr.util.jsonSafeValue(population.PreparedDataPopulation))) && ...
            string(sixgr.util.sha256Hex(uint8(unicode2native(char(ptoken),'UTF-8'))))== ...
                string(population.PreparedDataPopulationSHA256), ...
            'sixgr:report:PairedChannelSourceIdentity','Do not transplant or reconstruct the original preparation token.');
    else
        assert(isempty(fieldnames(population.PreparedDataPopulation)) && ...
            strlength(string(population.PreparedDataPopulationSHA256))==0, ...
            'sixgr:report:PairedChannelSourceIdentity','Missing historical preparation remains absent.');
    end
    for key=string(fieldnames(population.OriginalSourceRowPopulation)).'
        assert(ismember(key,a.SourceRow.Properties.VariableNames) && ...
            isequaln(population.OriginalSourceRowPopulation.(key),a.SourceRow.(key)), ...
            'sixgr:report:PairedChannelSourceIdentity','Original population projection differs from source row.');
    end
    % Only frozen source fields are asserted. Later annotation may add new
    % population fields; it cannot retroactively supply archive authority.
    keep=["RunID","ExecutionID","ConfigHash","ScenarioID","RunTag","Seed","RandomSeed", ...
        "ChannelSeed","SweepPointIndex","ConfiguredSNR_dB","UEIndex","RNTI","CellID","ServingCell", ...
        "Slot","ReceiverID","ReceiverWindowID","ReceiverClockDomain","ReceiverClockEpoch", ...
        "ObservationStartSample","ObservationEndSampleExclusive","ObservationSampleRateHz", ...
        "ReceiverObservationSHA256","ChannelObservationID"];
    for key=keep(ismember(keep,a.SourceRow.Properties.VariableNames))
        if ~localPresent(a.SourceRow.(key)), continue; end
        assert(ismember(key,row.Properties.VariableNames), ...
            'sixgr:report:PairedChannelSourceIdentity','Original source identity %s disappeared.',key);
        assert(isequaln(a.SourceRow.(key),row.(key)), ...
            'sixgr:report:PairedChannelSourceIdentity','Do not transplant/relabel the original source row (%s).',key);
    end
    for k=1:numel(a.Comparisons)
        c=a.Comparisons(k);
        if isempty(fieldnames(c.Operands)), continue; end
        o=c.Operands;
        [score,values,recomputed]=sixgr.report.scoreDMRSCSIRSCommonOperands( ...
            o.DMRSEstimate,o.CSIRSPortEstimate,o.PhysicalReference, ...
            o.CSIRSPortToPhysicalMatrix,o.DMRSLayerToPhysicalMatrices,o.Support);
        selected=resources.ResourceID==c.ResourceID & resources.ResourceOrdinal0==c.ResourceOrdinal0;
        assert(isequaln(score,c.Score) && isequaln(recomputed,o) && ...
            isequaln(resources(selected,values.Properties.VariableNames),values) && ...
            c.Evidence.ReceiverWindowID==a.Identity.ReceiverWindowID && ...
            ~c.Evidence.Reference.RFImpairmentsIncluded && ~c.Evidence.ReferenceUsedByReceiver, ...
            'sixgr:report:PairedChannelOperandClosure','Readback operands must reproduce the exact energies and owner identity.');
        planes=localReceiverPlanes(a,c.Evidence,row);
        if ~score.Available, continue; end
        out=table(n,a.ObservationID,a.ObservationID,c.ResourceID,score.ComparedValues, ...
            score.DMRSNMSELinear,score.CSIRSNMSELinear,score.DeltaNMSELinear,score.DeltaNMSE_dB, ...
            score.DeltaNMSEdBAvailable,string(score.Status), ...
            'VariableNames',{'SourceTrialRow','DMRSObservationID','CSIRSObservationID','CSIRSResourceID', ...
            'ComparedValues','DMRSNMSELinear','CSIRSNMSELinear','DeltaNMSELinear','DeltaNMSE_dB', ...
            'DeltaNMSEdBAvailable','PairingStatus'});
        out.ReferencePlane=o.ReferencePlane; out.MeasurementPlane=o.MeasurementPlane;
        out.ResourcesCSV=string(row.DMRSCSIRSComparisonCSV);
        out.ResourcesCSVSHA256=string(row.DMRSCSIRSComparisonCSVSHA256);
        out.ArchiveMAT=path; out.ArchiveMATSHA256=string(row.DMRSCSIRSComparisonMATFileSHA256);
        out.EvidenceScope="engineering_same_capture_comparison_not_normative_or_statistically_qualified";
        out.StatisticallyQualified=false;
        out.PostRFSampleSHA256=planes.PostRFSampleSHA256;
        out.ReceiverPlaneBindingSource=planes.Source;
        out.ReceiverPlaneBindingSHA256=planes.SHA256;
        out.PreparedDataPopulationJSON=ptoken;
        out.PreparedDataPopulationSHA256=string(population.PreparedDataPopulationSHA256);
        requiredPopulation=["RunID","ExecutionID","ConfigHash","SweepPointIndex","SourceRandomSeed","SourceChannelSeed"];
        out.PopulationScopeComplete=all(isfield(population.PreparedDataPopulation,cellstr(requiredPopulation)));
        if out.PopulationScopeComplete
            out.PopulationScopeComplete=all(arrayfun(@(key)localPresent(population.PreparedDataPopulation.(key)),requiredPopulation));
        end
        % Preserve supplied identity/value/type. Do not derive lifecycle from
        % folder names, current callback state, repeated local IDs or means.
        for key=keep
            if ismember(key,a.SourceRow.Properties.VariableNames), out.(key)=a.SourceRow.(key); end
        end
        pairs=localAppend(pairs,out);
    end
end
end

function planes=localReceiverPlanes(a,e,row)
% v1 mislabeled the raw post-RF hash as ReceiverObservationSHA256. Its
% immutable bytes stay untouched. Different bytes require the ORIGINAL
% completed-application capsule. Equal canonical sample hashes retain the
% historical exact-byte path; they do not establish that AGC was disabled.
% v2 names both planes and retains the actual gain-transformation receipt.
id='sixgr:report:PairedChannelReceiverPlaneBinding';
if a.Contract=="same_execution_paired_DMRS_CSI_RS_archive/v1"
    assert(string(e.Contract)=="same_execution_paired_DMRS_CSI_RS/v1",id,'Archive/evidence versions differ.');
    if string(e.ReceiverObservationSHA256)==string(a.Identity.ReceiverObservationSHA256)
        assert(string(e.ReceiverWindowID)==string(a.Identity.ReceiverWindowID) && ...
            string(e.DataTransmissionIdentity.TransmissionID)==string(a.Identity.TransmissionID), ...
            id,'Identical sample bytes cannot be attached to another window or data transmission.');
        for name=["ObservationStartSample","ObservationEndSampleExclusive","ObservationSampleRateHz","ReceiverID"]
            if ismember(name,a.SourceRow.Properties.VariableNames) && localPresent(a.SourceRow.(name))
                assert(localEqual(e.(name),a.SourceRow.(name)),id,'Original equal-byte capture field %s differs.',name);
            end
        end
        planes=struct('PostRFSampleSHA256',string(e.ReceiverObservationSHA256), ...
            'Source',"historical_v1_identical_canonical_sample_bytes_not_AGC_state",'SHA256',"");
        return;
    end
    names={'CompletedCSIApplicationEvidenceJSON','CompletedCSIApplicationEvidenceSHA256'};
    assert(all(ismember(names,row.Properties.VariableNames)),id, ...
        'Historical pairs require their original completed-application capsule; no current-config backfill.');
    token=string(row.CompletedCSIApplicationEvidenceJSON); sha=string(row.CompletedCSIApplicationEvidenceSHA256);
    assert(isscalar(token) && ~ismissing(token) && strlength(token)>0 && sha==localSHA(token),id, ...
        'The original completed-application JSON and hash must match.');
    b=jsondecode(char(token));
    required={'Version','Source','WaveformApplicationVerified','FullScenarioQualified','AdditionalPHYExecutions', ...
        'ReceiverWindowID','ReceiverID','TransmitterID','TransmissionIdentity','ReceiverInput','PostRFSampleSHA256', ...
        'TXSampleSHA256','ReceiverClockDomain','ReceiverClockEpoch','CompletedAtSample','ReceivedControl', ...
        'PreparedSourcePopulationJSON','PreparedSourcePopulationSHA256'};
    assert(isstruct(b) && isscalar(b) && all(isfield(b,required)) && ...
        string(b.Version)=="completed_received_csi_application/v1" && ...
        string(b.Source)=="received_CSI_owner_control_record_and_completed_shared_PDSCH" && ...
        isequal(b.WaveformApplicationVerified,true) && isequal(b.FullScenarioQualified,false) && ...
        isequal(b.AdditionalPHYExecutions,0),id,'Require the actual completed receipt, not a started/frozen claim.');
    assert(string(b.PostRFSampleSHA256)==string(e.ReceiverObservationSHA256) && ...
        string(b.TXSampleSHA256)==string(e.TransmitterObservationSHA256) && ...
        string(b.ReceiverClockDomain)=="shared_receiver_sample_clock/v1" && ...
        isequal(b.ReceiverClockEpoch,double(e.PhysicalConfigurationEpoch)) && ...
        isfinite(b.CompletedAtSample) && b.CompletedAtSample>=e.ObservationEndSampleExclusive && ...
        b.CompletedAtSample>=e.DataTransmissionIdentity.EndSampleExclusive && ...
        b.ReceivedControl.AvailableAtSample<=e.ObservationEndSampleExclusive,id, ...
        'The retained capsule must bind original raw/TX bytes, physical epoch and completed clocks.');
    localFieldsEqual(b.TransmissionIdentity,e.DataTransmissionIdentity,id);
    p=a.Identity.Population;
    assert(string(b.PreparedSourcePopulationJSON)==string(p.PreparedDataPopulationJSON) && ...
        string(b.PreparedSourcePopulationSHA256)==string(p.PreparedDataPopulationSHA256),id, ...
        'The original preparation population cannot be replaced by a later callback population.');
    for name=string(names)
        if ismember(name,a.SourceRow.Properties.VariableNames)
            assert(localEqual(row.(name),a.SourceRow.(name)),id,'Never replace an already retained completed capsule.');
        end
    end
    planes=struct('PostRFSampleSHA256',string(b.PostRFSampleSHA256), ...
        'Source',"historical_v1_original_completed_application_capsule",'SHA256',sha);
else
    assert(string(e.Contract)=="same_execution_paired_DMRS_CSI_RS/v2" && ...
        all(isfield(e,{'PostRFSampleSHA256','ReceiverPlaneBinding','ReceiverPlaneBindingJSON', ...
        'ReceiverPlaneBindingSHA256'})),id,'v2 requires explicit raw and receiver-input planes.');
    token=string(e.ReceiverPlaneBindingJSON); sha=string(e.ReceiverPlaneBindingSHA256); b=e.ReceiverPlaneBinding;
    assert(token==string(jsonencode(sixgr.util.jsonSafeValue(b))) && sha==localSHA(token) && ...
        all(isfield(a.Identity,{'PostRFSampleSHA256','ReceiverPlaneBindingSHA256'})) && ...
        sha==string(a.Identity.ReceiverPlaneBindingSHA256) && ...
        string(e.PostRFSampleSHA256)==string(a.Identity.PostRFSampleSHA256) && ...
        string(b.PostRFSampleSHA256)==string(e.PostRFSampleSHA256) && ...
        string(e.ReceiverObservationSHA256)==string(a.Identity.ReceiverObservationSHA256) && ...
        string(b.Contract)=="completed_shared_receiver_planes/v1" && ...
        string(b.Source)=="original_completed_decoder_input_and_executed_post_ADC_gain_trace" && ...
        string(b.PostRFHashPlane)=="actual_post_rx_rf_post_adc_samples" && ...
        b.PhysicalConfigurationEpoch==e.PhysicalConfigurationEpoch && ...
        b.AdditionalReceiverExecutions==0,id,'Keep the exact original two-plane transformation token.');
    localGainExecutions(b,e,id);
    planes=struct('PostRFSampleSHA256',string(b.PostRFSampleSHA256), ...
        'Source',string(b.Source),'SHA256',sha);
end
assert(string(b.ReceiverWindowID)==string(e.ReceiverWindowID) && ...
    string(b.ReceiverWindowID)==string(a.Identity.ReceiverWindowID) && ...
    string(b.ReceiverID)==string(e.ReceiverID) && string(b.TransmitterID)==string(e.TransmitterID), ...
    id,'Both sample planes must belong to the same original receiver window and endpoints.');
if isfield(b,'TransmissionIdentity'), tx=b.TransmissionIdentity.TransmissionID;
else, tx=b.TransmissionID;
end
assert(string(tx)==string(a.Identity.TransmissionID) && ...
    string(tx)==string(e.DataTransmissionIdentity.TransmissionID),id,'No other data transmission may supply the bridge.');
r=b.ReceiverInput;
required=fieldnames(sixgr.link.receivedWaveformEvidence());
assert(isstruct(r) && isscalar(r) && all(isfield(r,required)) && ...
    string(r.ReceiverObservationSHA256)==string(a.Identity.ReceiverObservationSHA256) && ...
    string(r.ReceiverObservationHashPlane)=="actual_receiver_input_before_synchronization" && ...
    string(r.ReceiverObservationHashSerialization)=="WaveformHash.runtimeArray_class_dimensions_real_imag_double" && ...
    string(r.ObservationCoverageSource)=="complete_contiguous_received_sample_buffer" && ...
    isequal(r.RuntimeStageWaveformsUsed,true) && ...
    r.ObservationStartSample==e.ObservationStartSample && ...
    r.ObservationEndSampleExclusive==e.ObservationEndSampleExclusive && ...
    r.ObservationSampleRateHz==e.ObservationSampleRateHz && ...
    r.ObservationCompletionTime_s==e.ObservationEndSampleExclusive/e.ObservationSampleRateHz, ...
    id,'Require the exact completed decoder-input plane, bounds, clock and coverage.');
for name=string(fieldnames(r)).'
    assert(ismember(name,a.SourceRow.Properties.VariableNames) && ismember(name,row.Properties.VariableNames) && ...
        localEqual(r.(name),a.SourceRow.(name)) && localEqual(r.(name),row.(name)), ...
        id,'Original decoder-input field %s must survive without relabeling.',name);
end
end

function localGainExecutions(b,e,id)
g=b.GainCompensation;
assert(string(g.Source)=="actual_receiver_applied_analog_gain_trace_after_ADC" && ...
    string(g.InputPlane)=="actual_post_rx_rf_post_adc_samples" && ...
    string(g.OutputPlane)=="digital_gain_compensated_received_samples_before_fft" && ...
    g.StartSample==e.ObservationStartSample && g.EndSampleExclusive==e.ObservationEndSampleExclusive && ...
    isequal(g.ClippingReconstructed,false) && isequal(g.QuantizationRemoved,false), ...
    id,'Do not conflate gain calibration with RF/noise/clipping removal.');
executed=b.OriginalGainExecutions; next=e.ObservationStartSample;
assert(iscell(executed) && ~isempty(executed),id,'Retain actual original gain executions, not inferred summary gains.');
gainMin=Inf; gainMax=-Inf; enabled=false;
for k=1:numel(executed)
    x=executed{k}; first=x.ExecutionStartSample; last=x.ExecutionEndSampleExclusive;
    a=x.ObservationStartSample; z=x.ObservationEndSampleExclusive;
    assert(isfinite(first) && isfinite(last) && first==fix(first) && last==fix(last) && ...
        a==next && a==max(first,e.ObservationStartSample) && z==min(last,e.ObservationEndSampleExclusive) && ...
        z>a && string(x.ReceiverID)==string(e.ReceiverID) && ...
        x.ConfigurationEpoch==e.PhysicalConfigurationEpoch && x.SampleRateHz==e.ObservationSampleRateHz, ...
        id,'Gain intervals must cover this endpoint and physical clock exactly once.');
    if string(x.AGCControlModel)=="disabled"
        assert(isstruct(x.OriginalGainTrace) && isempty(fieldnames(x.OriginalGainTrace)),id, ...
            'Do not manufacture a gain trace for a disabled AGC.');
        gainMin=min(gainMin,0); gainMax=max(gainMax,0);
    else
        t=x.OriginalGainTrace; v=t.AppliedGain_dB;
        assert(t.StartSample==first && t.EndSampleExclusive==last && isnumeric(v) && isreal(v) && ...
            numel(v)==last-first && all(isfinite(v),'all'),id,'Retain the original finite per-sample trace.');
        selected=v(a-first+(1:z-a)); gainMin=min(gainMin,min(selected)); gainMax=max(gainMax,max(selected));
        enabled=true;
    end
    next=z;
end
assert(next==e.ObservationEndSampleExclusive && isequal(g.Applied,enabled) && ...
    g.AppliedGainMin_dB==gainMin && g.AppliedGainMax_dB==gainMax,id, ...
    'The transformation summary must describe the retained original gain trace on this exact window.');
end

function localFieldsEqual(left,right,id)
assert(isstruct(left) && isscalar(left) && isequal(sort(fieldnames(left)),sort(fieldnames(right))),id, ...
    'The transmission identity schema must match the original owner receipt.');
for name=string(fieldnames(right)).'
    assert(localEqual(left.(name),right.(name)),id,'Original transmission field %s differs.',name);
end
end

function tf=localEqual(a,b)
% JSON scalar text containers differ from MATLAB strings. Preserve values;
% no trimming, coercion of missing values or tolerance for numeric changes.
if (ischar(a)||isstring(a)) && (ischar(b)||isstring(b))
    tf=isequaln(string(a),string(b));
elseif (isnumeric(a)||islogical(a)) && (isnumeric(b)||islogical(b))
    tf=isequaln(double(a),double(b));
else, tf=isequaln(a,b);
end
end

function sha=localSHA(token)
sha=string(sixgr.util.sha256Hex(uint8(unicode2native(char(token),'UTF-8'))));
end

function tf=localPresent(value)
if isnumeric(value), tf=~isempty(value) && all(isfinite(value),'all');
elseif isstring(value) || ischar(value), tf=all(~ismissing(string(value)) & strlength(strtrim(string(value)))>0,'all');
else, tf=false;
end
end

function a=localAppend(a,b)
if isempty(a), a=b; return; end
for name=setdiff(b.Properties.VariableNames,a.Properties.VariableNames,'stable')
    a.(name{1})=localMissing(b.(name{1}),height(a));
end
for name=setdiff(a.Properties.VariableNames,b.Properties.VariableNames,'stable')
    b.(name{1})=localMissing(a.(name{1}),height(b));
end
a=[a;b(:,a.Properties.VariableNames)];
end

function value=localMissing(prototype,n)
if isstring(prototype), value=strings(n,1); value(:)=missing;
elseif isnumeric(prototype), value=nan(n,1);
else, error('sixgr:report:PairedChannelIdentityType','Missing identity has no safe representation for %s.',class(prototype));
end
end
function path=localPath(root,relative)
assert(~ismissing(relative) && strlength(relative)>0 && ...
    isempty(regexp(char(relative),'(^[\\/]|^[A-Za-z]:|(^|[\\/])\.\.([\\/]|$))','once')), ...
    'sixgr:report:PairedChannelRunScope','References must stay inside the declared source run.');
path=fullfile(root,relative);
end
