function plotPUCCHDetectorComparison(summary,outputPath)
% Render actual component counts with stable contrast across MATLAB themes.
required={'Policy','NoiseOnlyTrials','FalseDetections','FalseACKBits', ...
    'DTXToACKBitProbability','QualificationStatus'};
assert(istable(summary) && height(summary)>0 && ...
    all(ismember(required,summary.Properties.VariableNames)), ...
    'sixgr:report:MissingPUCCHDetectorEvidence','Supply the actual detector comparison table.');
values=double(summary{:,{'NoiseOnlyTrials','FalseDetections','FalseACKBits'}});
assert(all(isfinite(values),'all') && all(values>=0,'all') && ...
    all(values==fix(values),'all') && all(values(:,1)>0) && ...
    all(values(:,3)<=values(:,2) & values(:,2)<=values(:,1)) && ...
    all(abs(summary.DTXToACKBitProbability-values(:,3)./values(:,1))<1e-12) && ...
    all(string(summary.QualificationStatus)=="not_qualified_component_sample_only"), ...
    'sixgr:report:InvalidPUCCHDetectorEvidence','Counts/denominators must be real component observations.');
fig=figure('Visible','off','Color','white','Position',[100 100 900 520]);
cleanup=onCleanup(@()close(fig)); %#ok<NASGU>
ax=axes(fig,'Color','white','XColor','black','YColor','black','TickLabelInterpreter','none');
bar(ax,categorical(string(summary.Policy)),[summary.FalseDetections summary.FalseACKBits]);
set(ax,'Color','white','XColor','black','YColor','black');
legend(ax,{'Any false detection','False ACK bits'},'Location','northeast', ...
    'TextColor','black','Color','white');
ylabel(ax,'Observed count (one HARQ bit per noise-only occasion)','Color','black');
title(ax,{'PUCCH Format 0: paired retained-IQ component replay', ...
    'Not baseline/conformance qualification; denominators in source CSV'},'Color','black');
ylim(ax,[0 max(summary.NoiseOnlyTrials)]); grid(ax,'on');
exportgraphics(fig,outputPath,'BackgroundColor','white','Resolution',150);
end
