function [T,score]=buildReceiverChannelEstimateTable(estimate,reference,indices,context)
% Measured pilot Hest and independently applied reference, all RX/port axes.
% Post-reception publication only. Never fit phase/gain, hide invalid pilots,
% invent physical DM-RS identities, or feed the reference to the receiver.
required={'Channel','Slot','UEIndex','ConfiguredSNR_dB', ...
    'ChannelEstimateSource','ChannelReferenceSource','ChannelReferencePlane'};
assert(isstruct(context) && isscalar(context) && all(isfield(context,required)), ...
    'sixgr:report:MissingChannelEstimateContext', ...
    'Receiver channel tables require explicit observation identity and both measurement sources.');
for field=["ChannelEstimateSource","ChannelReferenceSource","ChannelReferencePlane"]
    assert(isTextScalar(context.(field)) && strlength(string(context.(field)))>0, ...
        'sixgr:report:MissingChannelEstimateSource','Do not infer channel-reference provenance.');
end
if isstruct(estimate)
    snapshot=estimate;
    shape=[size(reference,1) size(reference,2) size(reference,3) size(reference,4)];
    assert(any(string(context.Channel)==["PDSCH","PUSCH"]) && ...
        snapshot.Contract==string(context.Channel)+"_pilot_channel_capture/v1" && ...
        isequal(snapshot.GridShape,shape) && isequal(snapshot.PilotIndices,indices) && ...
        isequal(size(snapshot.PilotChannelValues),[numel(indices) shape(3)]), ...
        'sixgr:report:ChannelSnapshotMismatch','Compact observations must retain exact resource and branch identity.');
    estimate=complex(nan(shape));
    [k,l,p]=ind2sub(shape([1 2 4]),double(indices(:)));
    for r=1:shape(3)
        estimate(sub2ind(shape,k,l,repmat(r,size(k)),p))=snapshot.PilotChannelValues(:,r);
    end
end
score=sixgr.phy.srs.pilotChannelNMSE(estimate,reference,indices);
K=size(estimate,1); L=size(estimate,2); R=size(estimate,3); P=size(estimate,4);
[k,l,p]=ind2sub([K L P],double(indices(:)));
n=numel(k); count=n*R;
subcarrier=repmat(k-1,R,1); symbol=repmat(l-1,R,1);
port=repmat(p-1,R,1); branch=repelem((0:R-1).',n);
at=sub2ind([K L R P],subcarrier+1,symbol+1,branch+1,port+1);
h=double(estimate(at)); truth=double(reference(at));
T=table(repmat(string(context.Channel),count,1), ...
    repmat(double(context.Slot),count,1),repmat(double(context.UEIndex),count,1), ...
    repmat(double(context.ConfiguredSNR_dB),count,1),subcarrier,symbol,branch,port, ...
    real(h),imag(h),abs(h),angle(h),real(truth),imag(truth), ...
    abs(h-truth).^2,abs(truth).^2, ...
    repmat(string(context.ChannelEstimateSource),count,1), ...
    repmat(string(context.ChannelReferenceSource),count,1), ...
    repmat(string(context.ChannelReferencePlane),count,1), ...
    false(count,1),false(count,1), ...
    'VariableNames',{'Channel','Slot','UEIndex','ConfiguredSNR_dB', ...
    'SubcarrierIndex0','SymbolIndex0','RxBranchIndex0','ReferencePortIndex0', ...
    'HReal','HImag','Magnitude','Phase_rad','ReferenceHReal','ReferenceHImag', ...
    'ChannelErrorEnergy','ReferenceChannelEnergy','ChannelEstimateSource', ...
    'ChannelReferenceSource','ChannelReferencePlane', ...
    'ReferenceUsedByReceiver','GainOrPhaseFitted'});
assert(height(T)==score.ComparedComplexValueCount && ...
    abs(sum(T.ChannelErrorEnergy)-score.ErrorEnergy)<=64*eps(max(1,score.ErrorEnergy)) && ...
    abs(sum(T.ReferenceChannelEnergy)-score.ReferenceEnergy)<=64*eps(max(1,score.ReferenceEnergy)), ...
    'sixgr:report:ChannelEstimateEnergyMismatch', ...
    'Published resources must reproduce the complete independent channel-error calculation.');
end

function tf=isTextScalar(value)
tf=(ischar(value) && isrow(value)) || (isstring(value) && isscalar(value) && ~ismissing(value));
end
