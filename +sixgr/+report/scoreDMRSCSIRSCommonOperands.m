function [score,rows,operands]=scoreDMRSCSIRSCommonOperands(dmrs,csi,physicalReference,csiMap,dataMaps,support)
% Pure arithmetic, NOT proof of reception/execution. The shared owner binds
% original estimates, clock, pilots, reference and executed maps separately.
% No fit to Hhat/Hreference, no smoothing, no exporter interpolation.
R=size(dmrs,1); L=size(dmrs,2); Q=size(dmrs,3); P=size(csi,2); T=size(csiMap,1);
assert(Q>0 && isequal(size(support),[Q 2]) && ...
    all(isfinite(support),'all') && all(support>=0 & support==fix(support),'all') && ...
    size(unique(support,'rows'),1)==Q && size(csi,1)==R && size(csi,3)==Q && ...
    size(csiMap,2)==P && size(dataMaps,1)==T && size(dataMaps,2)==L && size(dataMaps,3)==Q && ...
    size(physicalReference,1)==R && size(physicalReference,2)==T && size(physicalReference,3)==Q, ...
    'sixgr:report:PairedChannelOperandShape','Require exact simultaneous branch/port/layer/support operands.');
assert(all(isfinite(dmrs),'all') && all(isfinite(csi),'all') && ...
    all(isfinite(physicalReference),'all') && all(isfinite(csiMap),'all') && all(isfinite(dataMaps),'all'), ...
    'sixgr:report:PairedChannelNonfiniteOperand','Never replace, drop or interpolate a missing native value.');
score=struct('Available',false,'Status',"incompatible_executed_CSI_port_to_DMRS_layer_span", ...
    'DMRSErrorEnergy',NaN,'CSIRSErrorEnergy',NaN,'ReferenceEnergy',NaN, ...
    'ComparedValues',0,'DMRSNMSELinear',NaN,'CSIRSNMSELinear',NaN, ...
    'DMRSNMSE_dB',NaN,'CSIRSNMSE_dB',NaN,'DeltaNMSELinear',NaN, ...
    'DeltaNMSE_dB',NaN,'DeltaNMSEdBAvailable',false);
rows=table(); operands=struct();
% An underdetermined/dependent port basis has no unique change of basis.
if rank(double(csiMap))~=P, return; end
projected=complex(zeros(R,L,Q,'like',csi)); reference=projected;
transforms=complex(zeros(P,L,Q,'like',csiMap)); residual=zeros(Q,1);
for q=1:Q
    x=double(csiMap)\double(dataMaps(:,:,q));
    residual(q)=norm(double(csiMap)*x-double(dataMaps(:,:,q)),'fro');
    if residual(q)>512*eps(max(1,norm(double(dataMaps(:,:,q)),'fro')))*max([T P L])
        return;
    end
    transforms(:,:,q)=x;
    projected(:,:,q)=csi(:,:,q)*x;
    reference(:,:,q)=physicalReference(:,:,q)*dataMaps(:,:,q);
end
de=abs(dmrs-reference).^2; ce=abs(projected-reference).^2; energy=abs(reference).^2;
score.DMRSErrorEnergy=sum(de,'all'); score.CSIRSErrorEnergy=sum(ce,'all');
score.ReferenceEnergy=sum(energy,'all'); score.ComparedValues=numel(reference);
score.Status="unavailable_zero_reference_energy";
if score.ReferenceEnergy>0
    score.Available=true; score.Status="paired_exact_common_operands";
    score.DMRSNMSELinear=score.DMRSErrorEnergy/score.ReferenceEnergy;
    score.CSIRSNMSELinear=score.CSIRSErrorEnergy/score.ReferenceEnergy;
    score.DMRSNMSE_dB=10*log10(score.DMRSNMSELinear);
    score.CSIRSNMSE_dB=10*log10(score.CSIRSNMSELinear);
    score.DeltaNMSELinear=score.DMRSNMSELinear-score.CSIRSNMSELinear;
    % Equal zero errors give -Inf/-Inf, not an invented zero dB delta.
    if score.DMRSErrorEnergy>0 && score.CSIRSErrorEnergy>0
        score.DeltaNMSE_dB=score.DMRSNMSE_dB-score.CSIRSNMSE_dB;
        score.DeltaNMSEdBAvailable=true;
    end
end
[branch,layer,at]=ndgrid(0:R-1,0:L-1,1:Q);
rows=table(support(at(:),1),support(at(:),2),branch(:),layer(:), ...
    real(dmrs(:)),imag(dmrs(:)),real(projected(:)),imag(projected(:)), ...
    real(reference(:)),imag(reference(:)),de(:),ce(:),energy(:), ...
    'VariableNames',{'SubcarrierIndex0','OFDMSymbolIndex0','ReceiveBranch0','Layer0', ...
    'DMRSHReal','DMRSHImag','CSIRSProjectedHReal','CSIRSProjectedHImag', ...
    'ReferenceHReal','ReferenceHImag','DMRSErrorEnergy','CSIRSErrorEnergy','ReferenceEnergy'});
operands=struct('DMRSEstimate',dmrs,'CSIRSPortEstimate',csi, ...
    'PhysicalReference',physicalReference,'CSIRSPortToPhysicalMatrix',csiMap, ...
    'DMRSLayerToPhysicalMatrices',dataMaps,'CSIRSPortToLayerTransforms',transforms, ...
    'SpanClosureResidual',residual,'Support',support,'GainOrPhaseFitted',false, ...
    'ProjectionSource',"exact_executed_spatial_amplitude_maps_not_fit_to_estimates", ...
    'ReferencePlane',"nominal_linear_effective_PDSCH_layer_on_actual_receiver_FFT_clock", ...
    'MeasurementPlane',"same_post_front_end_native_OFDM_grid_before_equalization");
end
