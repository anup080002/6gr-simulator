function out=collectCSISelectionObservations(T,fields,source)
% Original discrete decisions, NOT arithmetic means or a codebook accuracy test.
% Every observation keeps its own namespace/clock. Missing namespace fields
% remain missing; no cross-row or cross-point pooling is authorized here.
arguments
    T table
    fields string
    source (1,1) string
end
out=table('Size',[0 10],'VariableTypes', ...
    {'double','string','double','string','string','string','string','string','string','string'}, ...
    'VariableNames',{'SourceRowIndex','SourceField','ValueNumeric','ValueText','Unit', ...
    'SourceArtifact','PopulationID','PopulationJSON','SupportConfigurationJSON','Notes'});
if height(T)==0, return; end
vars=string(T.Properties.VariableNames);
identityFields=["RunID","RunTag","ExecutionID","ConfigHash","ScenarioID","Direction", ...
    "ConfiguredSNR_dB","SNR_dB","SweepPointIndex","RandomSeed","ChannelSeed", ...
    "UEIndex","UEID","RNTI","CellID","ServingCell","ResourceID","ResourceSetID", ...
    "ComponentCarrier","BWPID","BWPId","ReceiverID","ReceiverWindowID", ...
    "Frame","Slot","SFN","SlotConvention","ObservationID","ObservationStartSample", ...
    "ObservationEndSampleExclusive","ObservationSampleRateHz","ResultAvailableAtSample", ...
    "ReceiverObservationSHA256","PowerReferencePlane","PhysicalMeasurementReferencePlane", ...
    "RI","RankIndicator","RankEstimate","Layers","NumLayers","CodebookType","CodebookMode", ...
    "PMIType","PMICodebookMode","PMIComponentsJSON","CSISelectionQualitySelectedPMIComponentsJSON", ...
    "PMICodebookMatrixCSIPortsSHA256","AppliedPrecoderSHA256","AppliedPrecoderMatrixSHA256", ...
    "FrozenGrantContextId","GrantContextId","ReportID","CSIReportID","CQITable","MCSTable", ...
    "PMISource","CQISource","RISelectionSource","CRISelectionSource","Source", ...
    "DLMeasurementConfigurationFamily","DLMeasurementConfigurationSHA256","DLMeasurementNCellID", ...
    "DLMeasurementInstallationSHA256","DLMeasurementAuthorityRequired", ...
    "DLMeasurementAuthorityEligible","DLMeasurementAuthorityStatus","DLMeasurementAuthoritySource"];
for field=reshape(fields,1,[])
    if ~ismember(field,vars), continue; end
    raw=T.(field);
    assert(ismatrix(raw)&&size(raw,1)==height(T), ...
        'sixgr:report:SelectionShape','Discrete values must retain one original row.');
    for k=1:height(T)
        operand=raw(k,:); if iscell(operand)&&isscalar(operand), operand=operand{1}; end
        [value,token,present,shape]=localValue(operand,field);
        if ~present, continue; end
        unit="index";
        if ismember(field,["RI","RankIndicator","RankEstimate","EstimatedRI","Layers","NumLayers"]), unit="layers"; end
        id=struct('ContractVersion',"sixgr.report.discrete_selection_observation/v1", ...
            'SourceArtifact',source,'SourceRowIndex',k,'SourceField',field, ...
            'Unit',unit,'OriginalValueText',token, ...
            'ProvenanceScope',"retained_source_row_not_independent_reception_verification");
        for name=identityFields
            if ismember(name,vars)
                item=T.(name)(k,:); if iscell(item)&&isscalar(item), item=item{1}; end
                id.(name)=item;
            end
        end
        support=struct('ValueShape',shape,'OriginalValue',operand,'OriginalValueSize',size(operand), ...
            'Aggregation',"none_original_discrete_observation", ...
            'NamespaceScope',"original_present_fields_only_no_inferred_codebook_or_resource", ...
            'ConfiguredCandidateDomainValidated',false, ...
            'CrossObservationPoolingAuthorized',false,'StandardizedAccuracyQualified',false);
        identityJSON=string(jsonencode(sixgr.util.jsonSafeValue(id)));
        supportJSON=string(jsonencode(sixgr.util.jsonSafeValue(support)));
        note="Original discrete source selection; no averaging/interpolation of identifiers. "+ ...
            "Receiver recommendation, delivered feedback and applied grant remain separate original sources. "+ ...
            "This records an observation, not independent selection accuracy or a statistical population.";
        out(end+1,:)={k,field,value,token,unit,source, ...
            string(sixgr.util.sha256Hex(char(identityJSON))),identityJSON,supportJSON,note}; %#ok<AGROW>
    end
end
end

function [value,token,present,shape]=localValue(raw,field)
value=NaN; token=""; present=false; shape="scalar_index";
if isnumeric(raw)&&isreal(raw)
    numbers=double(raw);
    if isempty(numbers)||all(isnan(numbers),'all'), return; end
    if isscalar(numbers), token=string(sprintf('%.17g',numbers));
    else, token=string(jsonencode(raw)); end
elseif (isstring(raw)&&isscalar(raw))||(ischar(raw)&&isrow(raw))
    token=string(raw);
    if ismissing(token)||strlength(strtrim(token))==0||strcmpi(strtrim(token),"NaN"), return; end
    unavailable=["unavailable","not_available","not_applicable","not_emitted"];
    if any(strcmpi(strtrim(token),unavailable))|| ...
            any(startsWith(lower(strtrim(token)),unavailable+"_")), return; end
    trimmed=strtrim(token); numbers=str2double(trimmed);
    if isnan(numbers)&&startsWith(trimmed,"[")
        try, numbers=jsondecode(trimmed); catch
            error('sixgr:report:SelectionValue','Malformed original discrete selection token.');
        end
    end
else
    error('sixgr:report:SelectionType','Original selection must be numeric or scalar text, not cast from another type.');
end
assert(isnumeric(numbers)&&isreal(numbers)&&isvector(numbers)&& ...
    all(isfinite(numbers),'all')&&all(numbers>=0&numbers==fix(numbers)&numbers<flintmax,'all'), ...
    'sixgr:report:SelectionValue','Discrete selection must retain finite nonnegative integer operands.');
if numel(numbers)>1
    assert(contains(upper(field),"PMI"),'sixgr:report:SelectionShape', ...
        'Only an explicit PMI component vector may contain multiple indices in one observation.');
    shape="original_PMI_component_vector_not_scalar_index";
else
    value=double(numbers);
end
present=true;
end
