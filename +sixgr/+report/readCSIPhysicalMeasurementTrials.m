function T=readCSIPhysicalMeasurementTrials(path)
% Preserve canonical CSI text operands before CSV type inference can turn a
% singleton vector into a number. No missing columns/values are supplied.
T=table();
if ~isfile(path), return; end
options=detectImportOptions(path,'FileType','text','Delimiter',',', ...
    'VariableNamingRule','preserve');
schema=sixgr.truth.emptyCSIRSTrialTable();
types=struct();
for name=string(schema.Properties.VariableNames)
    if ismember(name,string(options.VariableNames))&&isstring(schema.(name))
        types.(name)='string';
    end
end
% buildIndependentCSIRSTrialRow adds these original measurement fields to
% the base schema as strings, including vectors of cardinality one.
measurementText=["MeasurementRelativeSource", ...
    "MeasurementRSRPPerReceiveAntenna_dB_re_UnitOccupiedRE_Es", ...
    "MeasurementRSRPPerResource_dB_re_UnitOccupiedRE_Es", ...
    "MeasurementRSSIPerReceiveAntenna_dB_re_UnitOccupiedRE_Es", ...
    "MeasurementRSRQAntennaAggregation","MeasurementRSSIPerReceiveAntenna_dBm", ...
    "MeasurementRSRQPerReceiveAntenna_dB","MeasurementRSSIAntennaAggregation", ...
    "MeasurementRSSIStatus","MeasurementSymbolIndices0Based","MeasurementPhysicalResourcesJSON", ...
    "MeasurementRSRPPerReceiveAntenna_dBm","MeasurementRSRPPerResource_dBm", ...
    "MeasurementResourceIDs","MeasurementAntennaAggregation","PhysicalMeasurementWaveformStatus", ...
    "PhysicalMeasurementWaveformSource","PhysicalMeasurementStatus", ...
    "PhysicalMeasurementStandard","MeasurementReceiverGainCorrectionSource", ...
    "ReferenceMeasuredSINRSource","ReferenceMeasuredSINRStatus", ...
    "ReferenceMeasuredSINRDomain","ReferenceSINRMeasurementJSON"];
for name=measurementText
    if ismember(name,string(options.VariableNames)), types.(name)='string'; end
end
% Malformed existing CSI evidence is an error, not a missing-file fallback.
T=sixgr.util.csvReadTable(path,'ColumnTypes',types);
end
