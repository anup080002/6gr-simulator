function T=readPBCHMeasurementTrials(path)
% Preserve original producer vector tokens before sparse CSV type inference.
% No unavailable values, scalar identities, or missing columns are invented.
T=table();
if ~isfile(path), return; end
options=detectImportOptions(path,'FileType','text','Delimiter',',', ...
    'VariableNamingRule','preserve');
% recoverSIB1FromWaveform / ssbPowerReferenceEvidence / the canonical PBCH
% collector serialize these variable-length operands as one string per row.
names=["SSBWindowReferenceRSRQPerReceiveAntenna_dB", ...
    "SS_RSRPPerReceiveAntenna_dBm","SS_RSRPRawObservedPerReceiveAntenna_dBm", ...
    "SSBWindowRSSIPerReceiveAntenna_dBm","SS_SINRPerReceiveAntenna_dB", ...
    "SSSINRDesiredPowerPerReceiveAntenna_W","SSSINRNoiseInterferencePowerPerReceiveAntenna_W", ...
    "SS_RSRPPerReceiveAntenna_dB_re_UnitOccupiedRE_Es", ...
    "SS_RSRPRawObservedPerReceiveAntenna_dB_re_UnitOccupiedRE_Es", ...
    "SSBWindowRSSIPerReceiveAntenna_dB_re_UnitOccupiedRE_Es", ...
    "ReferenceSignalTxEPREPerAntenna_dB_re_UnitOccupiedRE_Es", ...
    "SSSINRDesiredPowerPerReceiveAntenna_UnitOccupiedRE_Es", ...
    "SSSINRNoiseInterferencePowerPerReceiveAntenna_UnitOccupiedRE_Es"];
types=struct();
for name=names
    if ismember(name,string(options.VariableNames)), types.(name)='string'; end
end
% Malformed existing evidence must reach the strict vector parser, not be
% silently imported as numeric NaN or caught as an absent optional table.
T=sixgr.util.csvReadTable(path,'ColumnTypes',types);
end
