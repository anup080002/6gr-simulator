function verified=validateSharedChannelObservationArtifact(root,T)
% Verify persisted coefficients and CSV content, not export-success flags.
% This checks artifact consistency; PHY execution is covered by runtime tests.
arguments
    root {mustBeTextScalar}
    T table
end
required=["ChannelObservationID","ChannelObservationManifestJSON", ...
    "ChannelObservationManifestSHA256","ChannelObservationMATFile", ...
    "ChannelObservationMATFileSHA256","ChannelObservationSegmentsCSV", ...
    "ChannelObservationSegmentsCSVSHA256","ChannelObservationSegmentCount", ...
    "ChannelObservationSource","ChannelObservationReceiverEstimatorInput", ...
    "ChannelObservationStartSample","ChannelObservationEndSampleExclusive", ...
    "ChannelObservationSampleRateHz"];
assert(height(T)==1 && all(ismember(required,string(T.Properties.VariableNames))), ...
    'sixgr:channel:MissingChannelArtifactBinding','One complete primary observation binding is required.');
hash=string(T.ChannelObservationManifestSHA256);
assert(localHash(hash) && sixgr.phy.waveform.WaveformHash.bytes(T.ChannelObservationManifestJSON)==hash && ...
    string(T.ChannelObservationID)=="chobs_"+hash, ...
    'sixgr:channel:ChannelManifestHashMismatch','Channel observation identity must match the exact manifest bytes.');
m=jsondecode(T.ChannelObservationManifestJSON);
assert(string(m.Contract)=="actual_shared_channel_observation/v1" && ...
    string(m.Representation)=="sample_indexed_path_gains_and_filters_not_resource_grid_H" && ...
    string(m.Source)=="same_executed_NR_channel_path_gains_and_filters" && ...
    string(T.ChannelObservationSource)==string(m.Source) && ...
    isequal(m.ReceiverEstimatorInput,false) && isequal(m.RFIncluded,false) && ...
    isequal(m.LargeScaleLossApplied,false) && isequal(m.AdditionalChannelExecutions,0) && ...
    (isequal(T.ChannelObservationReceiverEstimatorInput,false) || ...
     isequal(T.ChannelObservationReceiverEstimatorInput,0)), ...
    'sixgr:channel:ChannelArtifactSourceMismatch','Do not substitute receiver estimates, RF waveforms or replayed coefficients.');
localInterval(m.ObservationStartSample,m.ObservationEndSampleExclusive);
validateattributes(m.SampleRateHz,{'numeric'},{'scalar','finite','positive','real'});
assert(m.ObservationStartSample==T.ChannelObservationStartSample && ...
    m.ObservationEndSampleExclusive==T.ChannelObservationEndSampleExclusive && ...
    m.SampleRateHz==T.ChannelObservationSampleRateHz, ...
    'sixgr:channel:ChannelArtifactObservationMismatch','Artifact and primary-row observation clocks must agree.');
for pair={ {'RxRFStreamStartSample','ObservationStartSample'}, ...
        {'RxRFStreamEndSampleExclusive','ObservationEndSampleExclusive'} }
    names=pair{1};
    if ismember(names{1},T.Properties.VariableNames)
        assert(isequal(T.(names{1}),m.(names{2})), ...
            'sixgr:channel:ChannelArtifactObservationMismatch','Do not bind channel evidence from a different RX observation.');
    end
end
token="channel_observation_"+hash;
matPath=localPath(root,T.ChannelObservationMATFile,"channel/mat/"+token+".mat");
csvPath=localPath(root,T.ChannelObservationSegmentsCSV,"channel/csv/"+token+"_segments.csv");
assert(localHash(T.ChannelObservationMATFileSHA256) && localHash(T.ChannelObservationSegmentsCSVSHA256) && ...
    sixgr.phy.waveform.WaveformHash.file(matPath)==string(T.ChannelObservationMATFileSHA256) && ...
    sixgr.phy.waveform.WaveformHash.file(csvPath)==string(T.ChannelObservationSegmentsCSVSHA256), ...
    'sixgr:channel:ChannelArtifactFileHashMismatch','Published channel file bytes must match the primary trial hashes.');
saved=load(matPath,'ManifestJSON','Captures');
assert(isfield(saved,'ManifestJSON') && isfield(saved,'Captures') && ...
    string(saved.ManifestJSON)==string(T.ChannelObservationManifestJSON) && ...
    iscell(saved.Captures) && ~isempty(saved.Captures) && ...
    numel(saved.Captures)==numel(m.Segments) && numel(saved.Captures)==T.ChannelObservationSegmentCount, ...
    'sixgr:channel:ChannelArtifactPayloadMismatch','The saved manifest and captured segments must match the primary binding.');
csv=sixgr.util.csvReadTable(csvPath,'TextType','string');
assert(height(csv)==numel(m.Segments),'sixgr:channel:ChannelArtifactCSVMismatch','CSV must contain every captured segment exactly once.');
bounds=zeros(numel(m.Segments),2);
arrayHash=@sixgr.channel.ChannelFactory.runtimeNumericArraySHA256;
for k=1:numel(m.Segments)
    s=m.Segments(k); c=saved.Captures{k}; r=c.Reference;
    localInterval(s.StartSample,s.EndSampleExclusive);
    localInterval(s.ExecutionStartSample,s.ExecutionEndSampleExclusive);
    ns=s.EndSampleExclusive-s.StartSample;
    assert(s.SegmentIndex==k && s.StartSample>=s.ExecutionStartSample && ...
        s.EndSampleExclusive<=s.ExecutionEndSampleExclusive && ...
        s.RuntimeChannelStartSample==s.ExecutionStartSample && ...
        s.RuntimeChannelEndSample==s.ExecutionEndSampleExclusive && ...
        c.LinkID==string(m.LinkID) && c.TX==string(m.TransmitterID) && c.RX==string(m.ReceiverID) && ...
        r.Source==string(m.Source) && r.StateKey==string(s.RuntimeChannelStateKey) && ...
        r.StartSample==s.StartSample && r.EndSampleExclusive==s.EndSampleExclusive && ...
        r.ExecutionStartSample==s.ExecutionStartSample && r.ExecutionEndSampleExclusive==s.ExecutionEndSampleExclusive && ...
        r.ObservationStartSample==m.ObservationStartSample && r.ObservationEndSampleExclusive==m.ObservationEndSampleExclusive && ...
        r.SampleRateHz==m.SampleRateHz && ~r.ReceiverEstimatorInput && r.AdditionalChannelExecutions==0 && ...
        ~r.LargeScaleLossApplied && ~r.RFIncluded && ~r.PhysicalPortMappingApplied, ...
        'sixgr:channel:ChannelArtifactSegmentMismatch','Coefficient segments must retain their exact link, state, execution and observation clocks.');
    dims=[ns size(r.PathGains,2) s.NumTransmitAntennas s.NumReceiveAntennas];
    assert(all(dims>0) && all(dims==fix(dims)) && ...
        isfloat(r.PathGains) && isfloat(r.PathFilters) && isfloat(r.SampleTimes_s) && ...
        all(isfinite(r.PathGains),'all') && all(isfinite(r.PathFilters),'all') && all(isfinite(r.SampleTimes_s),'all') && ...
        isequal([size(r.PathGains,1) size(r.PathGains,2) size(r.PathGains,3) size(r.PathGains,4)],dims) && ...
        isequal(reshape(jsondecode(s.PathGainDimensions),1,[]),dims) && ...
        size(r.PathFilters,2)==dims(2) && size(r.PathFilters,1)>0 && ...
        s.PathGainElementCount==numel(r.PathGains) && s.SampleTimeCount==ns && ...
        isequal(size(r.SampleTimes_s),[ns 1]) && ...
        all(abs(diff(r.SampleTimes_s)*m.SampleRateHz-1)<1e-6) && ...
        r.NumTransmitAntennas==s.NumTransmitAntennas && r.NumReceiveAntennas==s.NumReceiveAntennas && ...
        r.NormalizePathGains==s.NormalizePathGains && r.NormalizeChannelOutputs==s.NormalizeChannelOutputs && ...
        string(arrayHash(r.PathGains))==string(s.PathGainsSHA256) && ...
        string(arrayHash(r.PathFilters))==string(s.PathFiltersSHA256) && ...
        string(arrayHash(r.SampleTimes_s))==string(s.SampleTimesSHA256), ...
        'sixgr:channel:ChannelArtifactArrayMismatch','Validate actual coefficients, filters, times and dimensions; a file hash alone is insufficient.');
    assert(localHash(s.RuntimeChannelInputWaveformSHA256) && localHash(s.RuntimeChannelOutputWaveformSHA256), ...
        'sixgr:channel:ChannelArtifactExecutionHashMissing','Original full-processor waveform identities must remain present.');
    bounds(k,:)=[s.StartSample s.EndSampleExclusive];
    for name=string(fieldnames(s)).'
        localCSVValue(csv,k,name,s.(name));
    end
    localCSVValue(csv,k,'ChannelObservationID',T.ChannelObservationID);
    localCSVValue(csv,k,'ObservationStartSample',m.ObservationStartSample);
    localCSVValue(csv,k,'ObservationEndSampleExclusive',m.ObservationEndSampleExclusive);
    localCSVValue(csv,k,'CoefficientMATFile',T.ChannelObservationMATFile);
    localCSVValue(csv,k,'Source',m.Source);
end
inactive=m.InactiveIntervals;
if isempty(inactive), inactive=zeros(0,2); end
if isvector(inactive) && numel(inactive)==2, inactive=reshape(inactive,1,2); end
assert(isnumeric(inactive) && size(inactive,2)==2, ...
    'sixgr:channel:ChannelArtifactCoverageMismatch','Inactive TDD intervals must retain explicit start/end pairs.');
allBounds=sortrows([bounds;inactive],1);
assert(all(isfinite(allBounds),'all') && all(allBounds==fix(allBounds),'all') && ...
    all(allBounds(:,2)>allBounds(:,1)) && allBounds(1,1)==m.ObservationStartSample && ...
    allBounds(end,2)==m.ObservationEndSampleExclusive && ...
    all(allBounds(2:end,1)==allBounds(1:end-1,2)) && all(diff(bounds(:,1))>0), ...
    'sixgr:channel:ChannelArtifactCoverageMismatch','No missing, duplicated or overlapping active/inactive observation intervals are allowed.');
verified=struct('Manifest',m,'Segments',csv,'MATPath',string(matPath), ...
    'CSVPath',string(csvPath),'ValidationSource',"persisted_array_and_file_content_validation");
end

function path=localPath(root,relative,expected)
assert(isfolder(root) && string(relative)==expected, ...
    'sixgr:channel:ChannelArtifactPathMismatch','Use the content-addressed artifact path inside the declared run.');
base=string(javaObject('java.io.File',char(root)).getCanonicalPath());
path=string(javaObject('java.io.File',char(fullfile(root,relative))).getCanonicalPath());
assert(startsWith(path,base+filesep,'IgnoreCase',ispc) && isfile(path), ...
    'sixgr:channel:ChannelArtifactMissing','A real channel artifact inside the declared run is required.');
end
function ok=localHash(value)
ok=isscalar(string(value)) && ~ismissing(string(value)) && ...
    ~isempty(regexp(char(string(value)),'^[0-9a-f]{64}$','once'));
end
function localInterval(first,last)
assert(isscalar(first) && isscalar(last) && isfinite(first) && isfinite(last) && ...
    first>=0 && first==fix(first) && last==fix(last) && last>first, ...
    'sixgr:channel:ChannelArtifactClockMismatch','Artifact sample intervals must be finite, nonnegative and integral.');
end
function localCSVValue(T,k,name,expected)
assert(ismember(name,string(T.Properties.VariableNames)), ...
    'sixgr:channel:ChannelArtifactCSVMismatch','Missing CSV field %s.',name);
actual=T.(name)(k,:);
if islogical(expected)
    ok=isequal(actual,expected) || isequal(actual,double(expected)) || ...
        isequal(string(actual),string(expected));
elseif isnumeric(expected)
    if ~isnumeric(actual), actual=str2double(string(actual)); end
    ok=isequaln(actual,expected);
else
    actual=string(actual); expected=string(expected);
    ok=isequal(actual,expected) || (isscalar(actual) && ismissing(actual) && expected=="");
end
assert(ok,'sixgr:channel:ChannelArtifactCSVMismatch','CSV field %s disagrees with the captured manifest.',name);
end
