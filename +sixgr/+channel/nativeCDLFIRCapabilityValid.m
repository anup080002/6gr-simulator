function ok=nativeCDLFIRCapabilityValid(c)
% Validate retained isolated capability operands without another channel call.
ok=false;
required={'ContractVersion','Passed','RuntimeMATLABRelease','RuntimeMATLABVersion','RuntimeToolboxVersion', ...
    'Source','FilterRule','SwapRule','Checks','ExactCloneContinuation', ...
    'ExactSaveLoadContinuation','ProbeChannelExecutions','OriginalOwnerChannelExecutions', ...
    'OriginalPhysicalSamplesAdvanced','GlobalRNGUnchanged','SampleDensity', ...
    'SampleClass','SampleRateHz','Seed','InitialTime_s','OriginalDirectionSwapped', ...
    'NormalizeChannelOutputs','MeasurementOrAccuracyQualification'};
if ~isstruct(c)||~isscalar(c)||~all(isfield(c,required)),return;end
try
    toolbox=ver('5g');
    flags={'Passed','ExactCloneContinuation','ExactSaveLoadContinuation', ...
        'GlobalRNGUnchanged','OriginalDirectionSwapped','NormalizeChannelOutputs', ...
        'MeasurementOrAccuracyQualification'};
    assert(all(cellfun(@(name)islogical(c.(name))&&isscalar(c.(name)),flags)));
    assert(string(c.ContractVersion)=="sixgr.native_CDL_FIR_capability/v1"&& ...
        isequal(c.Passed,true)&&string(c.RuntimeMATLABRelease)==string(version('-release'))&& ...
        string(c.RuntimeMATLABVersion)==string(version)&& ...
        string(c.RuntimeToolboxVersion)==string(toolbox.Version)&& ...
        string(c.Source)=="isolated_private_seeded_native_clone_public_API_probe"&& ...
        string(c.FilterRule)=="original_public_getPathFilters_samplewise_gains"&& ...
        string(c.SwapRule)=="selected_FIR_reset_no_physical_time_advance"&& ...
        isequal(c.ExactCloneContinuation,true)&&isequal(c.ExactSaveLoadContinuation,true)&& ...
        isequal(c.ProbeChannelExecutions,9)&&isequal(c.OriginalOwnerChannelExecutions,0)&& ...
        isequal(c.OriginalPhysicalSamplesAdvanced,0)&&isequal(c.GlobalRNGUnchanged,true)&& ...
        isequal(c.SampleDensity,Inf)&&any(string(c.SampleClass)==["single","double"])&& ...
        isequal(c.MeasurementOrAccuracyQualification,false)&& ...
        islogical(c.OriginalDirectionSwapped)&&isscalar(c.OriginalDirectionSwapped)&& ...
        islogical(c.NormalizeChannelOutputs)&&isscalar(c.NormalizeChannelOutputs));
    validateattributes(c.SampleRateHz,{'double'},{'scalar','real','finite','positive'});
    validateattributes(c.Seed,{'double'},{'scalar','real','finite','integer','nonnegative'});
    validateattributes(c.InitialTime_s,{'double'},{'scalar','real','finite','nonnegative'});
    assert(iscell(c.Checks)&&numel(c.Checks)==6);
    for k=1:6
        q=c.Checks{k};
        assert(isstruct(q)&&isscalar(q)&&all(isfield(q,{'Stage','Swapped','Samples', ...
            'NumInputSignals','NumPaths','FilterSHA256','NativeOutputSHA256', ...
            'RelativeError','RelativeRoundoffBound'}))&&isequal(q.Stage,k));
        validateattributes(q.Samples,{'double'},{'scalar','finite','integer','positive'});
        validateattributes(q.NumInputSignals,{'double'},{'scalar','finite','integer','positive'});
        validateattributes(q.NumPaths,{'double'},{'scalar','finite','integer','positive'});
        bound=128*double(eps(char(c.SampleClass)))*max([q.NumPaths,q.NumInputSignals,1]);
        assert(isequal(q.RelativeRoundoffBound,bound));
        validateattributes(q.RelativeError,{'double'},{'scalar','real','finite','nonnegative','<=',bound});
        assert(isequal(q.Swapped,xor(c.OriginalDirectionSwapped,any(k==[3 4]))));
        for name=["FilterSHA256","NativeOutputSHA256"]
            token=q.(name);
            assert((isstring(token)&&isscalar(token))||(ischar(token)&&isrow(token)));
            assert(~isempty(regexp(char(token),'^[0-9a-f]{64}$','once')));
        end
    end
    ok=true;
catch
    % Invalid or foreign capability has no original-channel authority.
end
end
