function evidence=validateSharedRFExecutionEvidence(T)
% Validate the retained RF manifest against its primary-row identity/clock.
% This checks provenance consistency; sample-content hashes are produced by
% actual RF/capture owners, not reconstructed from configuration here.
evidence=struct('Ok',false,'AnyStageConfigured',false,'AnyStageExecuted',false, ...
    'AnyTXSegmentWaveformChanged',false,'AnyRXSegmentWaveformChanged',false, ...
    'Source',"retained_RF_execution_manifest_validation",'FailureReason',"");
try
    assert(istable(T) && height(T)==1,'RF:ManifestRowScope','One primary row is required.');
    payload=string(T.RFExecutionManifestJSON);
    digest=string(sixgr.util.sha256Hex(uint8(unicode2native(char(payload),'UTF-8'))));
    assert(digest==string(T.RFExecutionManifestSHA256) && ...
        string(T.RFImpairmentChainId)=="rfpath_"+digest, ...
        'RF:ManifestIdentityMismatch','RF manifest bytes and path identity must agree.');
    m=jsondecode(payload);
    assert(string(m.Contract)=="actual_shared_rf_observation/v1" && ...
        isscalar(m.SampleRateHz) && isfinite(m.SampleRateHz) && m.SampleRateHz>0, ...
        'RF:ManifestContract','Actual retained RF manifest and physical sample rate are required.');
    rxDigest=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(m.RX),'UTF-8'))));
    assert(string(T.RxRFImpairmentChainId)=="rfobs_"+rxDigest && ...
        localHash(m.RX.InputWaveformSHA256) && localHash(m.RX.OutputWaveformSHA256) && ...
        localHash(m.TX.OutputWaveformSHA256) && ...
        string(T.RxRFInputWaveformSHA256)==string(m.RX.InputWaveformSHA256) && ...
        string(T.RxRFOutputWaveformSHA256)==string(m.RX.OutputWaveformSHA256) && ...
        string(T.TxRFOutputWaveformSHA256)==string(m.TX.OutputWaveformSHA256), ...
        'RF:ManifestCaptureMismatch','Manifest capture hashes must bind to the primary row.');
    for endpoint=["TX","RX"]
        if endpoint=="TX", prefix="Tx"; else, prefix="Rx"; end
        capture=m.(endpoint); records=capture.ExecutedSegments;
        assert(isstruct(records) && ~isempty(records) && strlength(string(capture.NodeID))>0 && ...
            localInteger(capture.CaptureStartSample) && localInteger(capture.CaptureEndSampleExclusive) && ...
            capture.CaptureEndSampleExclusive>capture.CaptureStartSample && ...
            T.(prefix+"RFStreamStartSample")==capture.CaptureStartSample && ...
            T.(prefix+"RFStreamEndSampleExclusive")==capture.CaptureEndSampleExclusive, ...
            'RF:ManifestClockMismatch','Capture clocks must match primary row clocks.');
        previous=NaN;
        for k=1:numel(records)
            r=records(k);
            assert(string(r.RFProcessingMode)=="retained_sample_stream" && ...
                localInteger(r.RFStreamStartSample) && localInteger(r.RFStreamEndSampleExclusive) && ...
                r.RFStreamEndSampleExclusive>r.RFStreamStartSample && ...
                (k==1 || r.RFStreamStartSample==previous) && ...
                localInteger(r.RFConfigurationEpoch) && ...
                localHash(r.RFInputWaveformSHA256) && localHash(r.RFOutputWaveformSHA256), ...
                'RF:ManifestSegmentMismatch','RF records must preserve contiguous actual sample intervals and hashes.');
            assert(localInteger(r.RFConfiguredStageCount) && localInteger(r.RFExecutedStageCount) && ...
                r.RFExecutedStageCount==r.RFConfiguredStageCount && ...
                r.RFConfiguredStageCount==T.(prefix+"RFConfiguredStageCount") && ...
                r.RFExecutedStageCount==T.(prefix+"RFExecutedStageCount") && ...
                isscalar(r.RFStrictOk) && isequal(r.RFStrictOk,true), ...
                'RF:ManifestExecutionMissing','Every configured retained RF operator must have executed successfully.');
            evidence.AnyStageConfigured=evidence.AnyStageConfigured || r.RFConfiguredStageCount>0;
            evidence.AnyStageExecuted=evidence.AnyStageExecuted || r.RFExecutedStageCount>0;
            field="Any"+endpoint+"SegmentWaveformChanged";
            evidence.(field)=evidence.(field) || string(r.RFInputWaveformSHA256)~=string(r.RFOutputWaveformSHA256);
            previous=r.RFStreamEndSampleExclusive;
        end
        assert(records(1).RFStreamStartSample<=capture.CaptureStartSample && ...
            previous>=capture.CaptureEndSampleExclusive, ...
            'RF:ManifestCoverageGap','RF records must cover the complete capture.');
    end
    evidence.Ok=true;
catch cause
    evidence.FailureReason="invalid_retained_RF_manifest:"+string(cause.identifier);
end
end

function ok=localInteger(value)
ok=isnumeric(value) && isscalar(value) && isfinite(value) && value>=0 && value==fix(value);
end
function ok=localHash(value)
ok=isscalar(string(value)) && ~isempty(regexp(char(string(value)),'^[0-9a-fA-F]{64}$','once'));
end
