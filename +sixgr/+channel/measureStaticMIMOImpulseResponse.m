function [h, evidence] = measureStaticMIMOImpulseResponse(channelObject, numTx, numRx, sampleRate)
%MEASURESTATICMIMOIMPULSERESPONSE Measure an exact static toolbox-channel FIR.

numTx = max(1,round(double(numTx)));
numRx = max(1,round(double(numRx)));
sampleRate = double(sampleRate);
[padSamples,trimSamples] = sixgr.channel.ChannelFactory.resolveChannelDelaySamples( ...
    channelObject,sampleRate);
responseLength = max(1,padSamples + 1);
spacing = max(64,trimSamples + responseLength + 32);
probe = complex(zeros(numTx*spacing + spacing,numTx));
for tx = 1:numTx
    probe((tx-1)*spacing + 1,tx) = 1;
end
reset(channelObject);
try
    response = channelObject(probe);
catch ME
    error("sixgr:channel:ReciprocalImpulseProbeFailed", ...
        "Static reciprocal channel impulse probe failed: %s", ME.message);
end
if size(response,2) ~= numRx
    error("sixgr:channel:ReciprocalImpulseProbeDimensionMismatch", ...
        "Toolbox channel returned %d receive columns; expected %d.", ...
        size(response,2),numRx);
end
h = complex(zeros(responseLength,numRx,numTx));
for tx = 1:numTx
    first = (tx-1)*spacing + trimSamples + 1;
    last = first + responseLength - 1;
    if last > size(response,1)
        error("sixgr:channel:ReciprocalImpulseProbeTooShort", ...
            "Impulse probe did not contain the complete aligned response.");
    end
    h(:,:,tx) = response(first:last,:);
end
if any(~isfinite(real(h(:)))) || any(~isfinite(imag(h(:)))) || norm(h(:)) <= 0
    error("sixgr:channel:InvalidMeasuredReciprocalImpulse", ...
        "Measured static toolbox-channel impulse response is nonfinite or zero.");
end
evidence = struct( ...
    "SourceChannelClass",class(channelObject), ...
    "NumTransmitAntennas",double(numTx), ...
    "NumReceiveAntennas",double(numRx), ...
    "SampleRate_Hz",double(sampleRate), ...
    "OriginalChannelFilterDelay_samples",double(trimSamples), ...
    "OriginalChannelPad_samples",double(padSamples), ...
    "AlignedImpulseLength_samples",double(responseLength), ...
    "MeasurementMethod","deterministic_time_multiplexed_impulse_probe", ...
    "ApproximationMode","none_static_lti_exact", ...
    "TruthClassification","toolbox_channel_measured_impulse_truth");
end
