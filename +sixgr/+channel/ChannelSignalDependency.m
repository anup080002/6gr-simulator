classdef ChannelSignalDependency
    % Finite signal-input memory of the ORIGINAL executed channel owner.
    % This is not a channel estimate and it cannot initialize/reset/replay
    % a channel. Unsupported installations remain explicitly unavailable.
    % New installations prove native direction-reset semantics on isolated
    % copies; existing v1 receipts retain their R2026a scope. Elapsed idle
    % time alone never establishes a native FIR reset.
    methods (Static)
        function d=install(state,epoch)
            d=sixgr.channel.ChannelSignalDependency.describe(state,epoch);
            if ~d.Available, return; end
            if double(state.TotalAppliedSamples)~=0
                d.Available=false; d.Status="unavailable_adopted_live_channel_history";
                return;
            end
            d.InputHistoryStartSample=double(state.CurrentSampleIndex);
            d.ZeroInputHistoryAtOrigin=true;
            d.HistoryInitializationSource="original_fresh_zero_warmup";
            d.InitializationReceipt=struct('CurrentSampleIndex',state.CurrentSampleIndex, ...
                'TotalAppliedSamples',state.TotalAppliedSamples, ...
                'TotalIdleAdvancedSamples',state.TotalIdleAdvancedSamples, ...
                'WarmupSamples',state.WarmupSamples,'ResetCount',state.ResetCount);
        end

        function snapshot=beforeRetarget(state)
            snapshot=struct('StateKey',string(state.StateKey), ...
                'Direction',string(state.Direction),'CurrentSampleIndex',state.CurrentSampleIndex, ...
                'NumTxAnt',state.NumTxAnt,'NumRxAnt',state.NumRxAnt, ...
                'ResetCount',state.ResetCount,'TotalAppliedSamples',state.TotalAppliedSamples, ...
                'TotalObjectInputSamples',state.TotalObjectInputSamples, ...
                'NativeSwapped',false);
            if isa(state.Obj,'nrCDLChannel')
                snapshot.NativeSwapped=logical(state.Obj.TransmitAndReceiveSwapped);
            end
        end

        function d=afterRetarget(before,state,epoch,consumedZeroTailSamples)
            d=sixgr.channel.ChannelSignalDependency.describe(state,epoch);
            if ~d.Available, return; end
            assert(string(state.StateKey)==before.StateKey && ...
                string(state.Direction)~=before.Direction && ...
                state.CurrentSampleIndex==before.CurrentSampleIndex && ...
                state.ResetCount==before.ResetCount && ...
                state.TotalAppliedSamples==before.TotalAppliedSamples && ...
                state.TotalObjectInputSamples==before.TotalObjectInputSamples && ...
                state.NumTxAnt==before.NumRxAnt && state.NumRxAnt==before.NumTxAnt, ...
                'sixgr:channel:SignalDependencyRetarget', ...
                'A dependency reset must bind the original unchanged physical timeline and reversed endpoints.');
            if isa(state.Obj,'nrCDLChannel')
                assert(logical(state.Obj.TransmitAndReceiveSwapped)~=before.NativeSwapped && ...
                    string(state.Meta.RuntimeTDDReciprocityDirection)==string(state.Direction), ...
                    'sixgr:channel:SignalDependencyRetarget', ...
                    'Require the actual native swap, not a changed direction label.');
                source="original_native_direction_swap_filter_reset";
            else
                source="original_memoryless_direction_change";
            end
            validateattributes(consumedZeroTailSamples,{'numeric'}, ...
                {'scalar','real','finite','integer','nonnegative'});
            d.InputHistoryStartSample=double(state.CurrentSampleIndex);
            d.ZeroInputHistoryAtOrigin=true; d.HistoryInitializationSource=source;
            d.InitializationReceipt=struct('Before',before, ...
                'After',sixgr.channel.ChannelSignalDependency.beforeRetarget(state), ...
                'OriginalConsumedZeroTailSamples',consumedZeroTailSamples, ...
                'NativeSemantics',sixgr.util.structGet(d,'NativeSwapSemantics', ...
                    "R2026a_nrCDLChannel_swapTransmitAndReceive_selected_FIR_and_batch_reset"), ...
                'AdditionalChannelExecutions',0,'ElapsedIdleTimeUsedAsReset',false);
        end

        function receipt=bind(d,before,after,replay,first,stop)
            if isempty(fieldnames(d))
                receipt=struct('ContractVersion',"sixgr.channel.executed_signal_dependency/v1", ...
                    'Available',false,'Status',"unavailable_original_installation_receipt_missing", ...
                    'StartSample',first,'EndSampleExclusive',stop);
                return;
            end
            receipt=d; receipt.StartSample=first; receipt.EndSampleExclusive=stop;
            if ~d.Available, return; end
            assert(before.CurrentSampleIndex==first && after.CurrentSampleIndex==stop && ...
                string(before.StateKey)==d.StateKey && string(after.StateKey)==d.StateKey && ...
                string(after.Direction)==d.Direction && ...
                before.ResetCount==d.RuntimeResetCount && after.ResetCount==d.RuntimeResetCount && ...
                before.SampleRate_Hz==d.SampleRateHz && after.SampleRate_Hz==d.SampleRateHz && ...
                before.NumTxAnt==d.NumTxAnt && after.NumTxAnt==d.NumTxAnt && ...
                before.NumRxAnt==d.NumRxAnt && after.NumRxAnt==d.NumRxAnt && ...
                replay.RuntimeChannelStartSample==first && replay.RuntimeChannelEndSample==stop, ...
                'sixgr:channel:SignalDependencyExecution', ...
                'The receipt must describe this original successful current-direction channel interval.');
            if isa(after.Obj,'nrCDLChannel')
                assert(logical(after.Obj.TransmitAndReceiveSwapped)==d.NativeSwapped && ...
                    after.Obj.SampleRate==d.SampleRateHz && isinf(after.Obj.SampleDensity), ...
                    'sixgr:channel:SignalDependencyExecution','Installed native filtering authority changed.');
            end
        end
    end
    methods (Static,Access=private)
        function d=describe(state,epoch)
            validateattributes(epoch,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
            d=struct('ContractVersion',"sixgr.channel.executed_signal_dependency/v1", ...
                'Available',false,'Status',"unavailable_native_filter_authority", ...
                'SampleRateHz',double(state.SampleRate_Hz),'ConfigurationEpoch',double(epoch), ...
                'StateKey',string(state.StateKey),'Direction',string(state.Direction), ...
                'NumTxAnt',double(state.NumTxAnt),'NumRxAnt',double(state.NumRxAnt), ...
                'RuntimeResetCount',double(state.ResetCount),'MemorySamples',NaN, ...
                'InputHistoryStartSample',NaN,'ZeroInputHistoryAtOrigin',false, ...
                'HistoryInitializationSource',"",'FilterSHA256',"", ...
                'NativeInitializationSHA256',"",'NativeSwapped',false, ...
                'FilterSize',zeros(1,0),'InitializationReceipt',struct(), ...
                'NativeFilterAuthority',"",'AdditionalChannelExecutions',0);
            if sixgr.channel.IdentityAWGNRuntime.isState(state)
                d.Available=true; d.Status="available_executed_memoryless_linear_operator";
                d.MemorySamples=0; d.FilterSize=[1 1];
                d.FilterSHA256=string(sixgr.phy.waveform.WaveformHash.numeric(1));
                d.NativeInitializationSHA256="not_applicable_memoryless_operator";
                d.NativeFilterAuthority="executed_IdentityAWGNRuntime_memoryless_operator";
                return;
            end
            if ~isa(state.Obj,'nrCDLChannel'), return; end
            n=sixgr.util.structGet(state,'Meta.NativeReciprocalFilterInitialization',struct());
            required={'ContractVersion','Applied','Status','RuntimeMATLABRelease', ...
                'RuntimeToolboxVersion','SampleDensity','SampleRateHz','Seed', ...
                'PhysicalSamplesAdvanced','GlobalRNGUnchanged'};
            legacy=all(isfield(n,required)) && ...
                string(n.ContractVersion)=="sixgr.channel.FreshCDLReciprocalFilters/v1" && ...
                string(n.RuntimeMATLABRelease)=="2026a" && string(version('-release'))=="2026a" && ...
                string(n.RuntimeToolboxVersion)=="26.1";
            capable=all(isfield(n,[required {'NativeCapability','NativeCapabilitySHA256'}])) && ...
                string(n.ContractVersion)=="sixgr.channel.FreshCDLReciprocalFilters/v2" && ...
                sixgr.channel.nativeCDLFIRCapabilityValid(n.NativeCapability);
            if capable
                capable=isequal(n.NativeCapability.NormalizeChannelOutputs,logical(state.Obj.NormalizeChannelOutputs)) && ...
                    isequal(n.NativeCapability.SampleRateHz,n.SampleRateHz) && ...
                    isequal(n.NativeCapability.Seed,n.Seed) && ...
                    string(n.RuntimeMATLABRelease)==string(n.NativeCapability.RuntimeMATLABRelease) && ...
                    string(n.RuntimeToolboxVersion)==string(n.NativeCapability.RuntimeToolboxVersion) && ...
                    string(n.NativeCapabilitySHA256)==string(sixgr.util.sha256Hex( ...
                    uint8(unicode2native(jsonencode(n.NativeCapability),'UTF-8'))));
            end
            if ~(legacy||capable) || ...
                    ~n.Applied || string(n.Status)~="fresh_public_both_direction_setup_then_reset" || ...
                    ~isinf(n.SampleDensity) || ~isinf(state.Obj.SampleDensity) || ...
                    n.SampleRateHz~=state.SampleRate_Hz || state.Obj.SampleRate~=state.SampleRate_Hz || ...
                    n.Seed~=state.Obj.Seed || n.PhysicalSamplesAdvanced~=0 || ~n.GlobalRNGUnchanged
                return;
            end
            sixgr.channel.waveformChannelOutputContract(state.Obj);
            % Full public finite impulse response, never nominal delay
            % spread or epsilon-truncated taps. Initialization above binds
            % this public native authority to both actual reciprocal FIRs.
            filters=getPathFilters(state.Obj);
            assert(isnumeric(filters)&&ismatrix(filters)&&~isempty(filters)&&all(isfinite(filters),'all'), ...
                'sixgr:channel:SignalDependencyFilter','Retain actual finite native path filters.');
            d.MemorySamples=size(filters,1)-1; d.FilterSize=size(filters);
            d.FilterSHA256=string(sixgr.phy.waveform.WaveformHash.numeric(filters));
            d.NativeInitializationSHA256=string(sixgr.util.sha256Hex( ...
                uint8(unicode2native(jsonencode(n),'UTF-8'))));
            d.NativeSwapped=logical(state.Obj.TransmitAndReceiveSwapped);
            d.NativeFilterAuthority="R2026a_Inf_fresh_both_direction_public_getPathFilters";
            d.NativeSwapSemantics="R2026a_nrCDLChannel_swapTransmitAndReceive_selected_FIR_and_batch_reset";
            if capable
                d.NativeFilterAuthority="public_CDL_Inf_capability_verified_original_filters";
                d.NativeSwapSemantics="capability_verified_nrCDLChannel_selected_FIR_reset";
                d.NativeCapability=n.NativeCapability;
                d.NativeCapabilitySHA256=n.NativeCapabilitySHA256;
            end
            d.Available=true; d.Status="available_original_native_finite_FIR_support";
        end
    end
end
