function evidence=initializeFreshCDLReciprocalFilters(object,warmup)
%INITIALIZEFRESHCDLRECIPROCALFILTERS Preserve fresh native CDL fork state.
% MATLAB_BEHAVIOR, pinned R2026a: an unused native reciprocal filter loses
% its CDL-specific filter design setting through clone/save. Public setup in
% both directions followed by one public reset preserves that state. This
% preparation is NOT physical time and must precede ordinary warmup/idle.
% Never use this on a live/restored object or to repair historical evidence.
% Finite SampleDensity can use another native batch filter and is OUTSIDE
% this repair. No private toolbox property is read or changed here.
assert(isa(object,'nrCDLChannel'), ...
    'sixgr:channel:FreshCDLInitializationBackend','Only native nrCDLChannel is supported.');
assert(~isLocked(object),'sixgr:channel:FreshCDLInitializationRequiresUnlocked', ...
    'Initialization must precede the first physical sample; live owners cannot be reset.');
sixgr.channel.waveformChannelOutputContract(object);
assert(isinf(object.SampleDensity), ...
    'sixgr:channel:FreshCDLInitializationFiniteDensityUnsupported', ...
    'Finite-density reciprocal/batch initialization is not qualified by this repair.');
assert(string(object.RandomStream)=="mt19937ar with seed", ...
    'sixgr:channel:FreshCDLInitializationRequiresSeededStream', ...
    'Fresh preparation requires a private seeded stream, not the global RNG.');
assert(strcmp(version('-release'),'2026a'), ...
    'sixgr:channel:FreshCDLInitializationReleaseUnqualified', ...
    'The public fresh-initialization equivalence contract is qualified for R2026a only.');
validateattributes(warmup,{'single','double'},{'2d','nonempty','finite'});
assert(~issparse(warmup)&&all(warmup==0,'all'), ...
    'sixgr:channel:FreshCDLInitializationRequiresZeros', ...
    'Preparation may consume only the original zero warmup shape, never data samples.');
channelInfo=info(object);
numTx=double(channelInfo.NumInputSignals);
numRx=double(channelInfo.NumOutputSignals);
assert(size(warmup,2)==numTx, ...
    'sixgr:channel:FreshCDLInitializationDimensions', ...
    'Warmup columns must match the native current-direction input count.');
originalSwapped=logical(object.TransmitAndReceiveSwapped);
originalInitialTime=double(object.InitialTime);
originalSeed=double(object.Seed);
originalRNG=rng;
reverseWarmup=zeros(size(warmup,1),numRx,'like',warmup);
sixgr.channel.applyWaveformChannelOnce(object,warmup,false);
swapTransmitAndReceive(object);
sixgr.channel.applyWaveformChannelOnce(object,reverseWarmup,false);
swapTransmitAndReceive(object);
% This is the materialization boundary's one existing public reset, not a
% second reset on a physical channel. Ordinary warmup follows at the caller.
reset(object);
assert(logical(object.TransmitAndReceiveSwapped)==originalSwapped && ...
    double(object.InitialTime)==originalInitialTime && double(object.Seed)==originalSeed && ...
    isequal(rng,originalRNG),'sixgr:channel:FreshCDLInitializationStateChanged', ...
    'Fresh preparation must preserve direction, configured origin/seed and global RNG.');
toolbox=ver('5g');
evidence=struct('ContractVersion',"sixgr.channel.FreshCDLReciprocalFilters/v1", ...
    'Applied',true,'Status',"fresh_public_both_direction_setup_then_reset", ...
    'Backend',string(class(object)),'RuntimeMATLABRelease',string(version('-release')), ...
    'RuntimeToolboxVersion',string(toolbox.Version),'QualifiedMATLABRelease',"2026a", ...
    'QualifiedToolboxVersion',"26.1",'SampleDensity',double(object.SampleDensity), ...
    'InitialTime_s',originalInitialTime,'Seed',originalSeed, ...
    'InitialTransmitAndReceiveSwapped',originalSwapped, ...
    'SampleRateHz',double(object.SampleRate),'InitialNumInputSignals',numTx, ...
    'InitialNumOutputSignals',numRx,'SetupSampleClass',string(class(warmup)), ...
    'SetupSamplesComplex',~isreal(warmup),'SetupSamplesPerDirection',size(warmup,1), ...
    'DiscardedSetupSamples',2*size(warmup,1),'ResetCount',1, ...
    'PhysicalSamplesAdvanced',0,'GlobalRNGUnchanged',true, ...
    'FiniteDensityQualified',false,'HistoricalCheckpointRepaired',false, ...
    'Scope',"fresh_seeded_cpu_per_sample_CDL_filter_serialization");
end
