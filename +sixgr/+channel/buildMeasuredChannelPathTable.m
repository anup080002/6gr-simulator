function T=buildMeasuredChannelPathTable(verified,trial)
% Actual retained channel operators; neither configured PDP nor RS power.
% Linear power is averaged over time and antenna pairs. No complex-mean
% cancellation, path-power normalization, model replay or synthetic path.
rows=struct([]);
for k=1:numel(verified.Manifest.Segments)
    s=verified.Manifest.Segments(k);
    p=verified.PathMeanCoefficientPower{k};
    n=size(p,1);
    delays=decodeVector(s,'RuntimeChannelPathDelays_sJSON',n);
    angles=zeros(n,4);
    for a=1:4
        names=["AoD","AoA","ZoD","ZoA"];
        angles(:,a)=decodeVector(s,"RuntimeChannelAngles"+names(a)+"_degJSON",n);
    end
    powers=mean(reshape(p,n,[]),2);
    for j=1:n
        row=struct('ChannelObservationID',string(trial.ChannelObservationID), ...
            'Slot',value(trial,'Slot'),'UEIndex',value(trial,'UEIndex'), ...
            'RNTI',value(trial,'RNTI'),'ConfiguredSNR_dB',value(trial,'ConfiguredSNR_dB'), ...
            'SegmentIndex',k,'PathIndex',j,'StartSample',s.StartSample, ...
            'EndSampleExclusive',s.EndSampleExclusive,'SampleCount',s.SampleTimeCount, ...
            'ChannelModelApplied',string(s.ChannelModelApplied), ...
            'Delay_s',delays(j),'Delay_ns',1e9*delays(j), ...
            'AngleAoD_deg',angles(j,1),'AngleAoA_deg',angles(j,2), ...
            'AngleZoD_deg',angles(j,3),'AngleZoA_deg',angles(j,4), ...
            'MeanCoefficientPowerLinear',powers(j), ...
            'MeanCoefficientGain_dB',10*log10(powers(j)), ...
            'NumTxAntennas',s.NumTransmitAntennas,'NumRxAntennas',s.NumReceiveAntennas, ...
            'PerAntennaPairPowerJSON',string(jsonencode(reshape(p(j,:,:),s.NumTransmitAntennas,s.NumReceiveAntennas))), ...
            'AppliedLinkPathloss_dB',value(trial,'AppliedPathloss_dB'), ...
            'AppliedLinkLargeScaleGain_dB',value(trial,'AppliedLargeScaleGain_dB'), ...
            'LinkPathlossModelSource',textValue(trial,'PathlossModelSource'), ...
            'LinkPathlossStatus',textValue(trial,'PathlossComplianceStatus'), ...
            'PowerDefinition',string(verified.PathPowerDefinition), ...
            'PowerUnit',"dimensionless_channel_coefficient_magnitude_squared_not_dBm", ...
            'Source',"validated_same_execution_full_coefficient_archive", ...
            'CoefficientMATFile',string(trial.ChannelObservationMATFile), ...
            'CoefficientMATFileSHA256',string(trial.ChannelObservationMATFileSHA256), ...
            'PathGainsSHA256',string(s.PathGainsSHA256),'ReceiverEstimatorInput',false);
        if isempty(rows), rows=row; else, rows(end+1,1)=row; end %#ok<AGROW>
    end
end
T=struct2table(rows,'AsArray',true);
end

function x=decodeVector(s,name,n)
assert(isfield(s,name),'sixgr:channel:MissingExecutedPathMetadata');
x=double(jsondecode(s.(name))); x=x(:);
if isempty(x)
    x=nan(n,1); % Explicitly unavailable angles, never substitute geometry.
else
    assert(numel(x)==n,'sixgr:channel:ChannelPathMetadataCountMismatch');
end
end

function x=value(T,name)
x=NaN;
if ismember(name,string(T.Properties.VariableNames)), x=double(T.(name)(1)); end
end

function x=textValue(T,name)
x="unavailable";
if ismember(name,string(T.Properties.VariableNames)), x=string(T.(name)(1)); end
end
