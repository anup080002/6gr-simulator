classdef AppliedChannelReferenceStream
    % Full sample-domain reference propagation, with explicit value state.
    % This adapter never executes/resets a native channel or changes its
    % samples. It consumes the ORIGINAL complete ChannelFactory reference
    % and ChannelSignalDependency receipt. The caller owns their provenance;
    % matching supplied records is not proof of global owner identity.
    %
    % Initial scope: CPU double, R2026a CDL/Inf, original fresh initialization
    % or actual reciprocal reset. No TDL/interpolated/single qualification.
    % The existing FIR kernel is reused without receive-count normalization,
    % physical mapping, delay trimming, gain fitting or RF processing.
    % fromComponentBirth(binding,dependency,snapshot,birth) starts only an
    % independent zero COMPONENT FIR at the original interval boundary.
    % snapshot is the original ChannelSignalDependency.beforeRetarget(state)
    % value (obtaining it performs no retarget). birth uses the same declared
    % TX-component registration coordinates as AppliedTXLinearReferenceStream.
    % Neither supplied record establishes original queue/owner authority.
    properties (SetAccess=private)
        Binding
        Dependency
        NextSampleIndex
        ObjectTimeOffsetSamples
        ModelHistoryStartSample
        ComponentBirth = struct()
        OriginalBirthSnapshot = struct()
    end
    properties (Access=private)
        FilterState
        Normalization = []
    end
    methods
        function obj=AppliedChannelReferenceStream(binding,dependency,varargin)
            binding=localBinding(binding);
            localDependency(dependency,binding);
            assert(isempty(varargin)||numel(varargin)==2, ...
                'sixgr:channel:AppliedReferenceHistory','Supply both the original snapshot and declared birth.');
            if isempty(varargin)
                assert(string(dependency.HistoryInitializationSource)=="original_fresh_zero_warmup", ...
                    'sixgr:channel:AppliedReferenceHistory', ...
                    'A new ordinary stream requires the original fresh zero-history installation.');
                [offset,~]=localHistoryOrigin(dependency);
                first=dependency.InputHistoryStartSample;
            else
                snapshot=varargin{1}; birth=varargin{2};
                localBirth(birth,dependency);
                first=birth.ModelHistoryStartSample;
                localSnapshot(snapshot,dependency,first);
                assert(numel(fieldnames(snapshot))==9, ...
                    'sixgr:channel:AppliedReferenceHistory', ...
                    'Birth requires exactly the nine original snapshot fields; do not retain caller arrays.');
                [offset,originApplied]=localHistoryOrigin(dependency);
                assert(first<flintmax-offset && ...
                    snapshot.TotalObjectInputSamples-first==offset && ...
                    snapshot.TotalObjectInputSamples==first+offset && ...
                    snapshot.TotalAppliedSamples>=originApplied && ...
                    snapshot.TotalAppliedSamples-originApplied<=first-dependency.InputHistoryStartSample, ...
                    'sixgr:channel:AppliedReferenceHistory', ...
                    'Original native counters/offset must agree; component birth is not a native reset.');
                obj.ComponentBirth=birth; obj.OriginalBirthSnapshot=snapshot;
            end
            obj.Binding=binding; obj.Dependency=dependency;
            obj.NextSampleIndex=first; obj.ModelHistoryStartSample=first;
            obj.ObjectTimeOffsetSamples=offset;
            obj.FilterState=complex(zeros(dependency.MemorySamples,dependency.NumTxAnt, ...
                dependency.FilterSize(2)));
        end

        function [next,nativeSamples,desiredSamples,receipt]=advance(obj,componentSamples, ...
                originalInputChunk,reference,linkExecution)
            % linkExecution is the original execution.Links entry:
            % ID/TX/RX/Replay/LossReplay. This explicit wrapper binds endpoint
            % metadata; a standalone test must label its wrapper as declared.
            % componentSamples may differ from the original aggregate input.
            % Both identities are retained separately, never substituted.
            localFields(linkExecution,{'ID','TX','RX','Replay','LossReplay'},'Execution');
            assert(localText(linkExecution.ID,'Execution')==obj.Binding.LinkID && ...
                localText(linkExecution.TX,'Execution')==obj.Binding.TX && ...
                localText(linkExecution.RX,'Execution')==obj.Binding.RX, ...
                'sixgr:channel:AppliedReferenceExecution','Original link endpoints changed.');
            rp=linkExecution.Replay;
            localFields(rp,{'ChannelSignalDependency','RuntimeChannelStateUsed', ...
                'RuntimeChannelStateKey','RuntimeChannelStartSample','RuntimeChannelEndSample', ...
                'RuntimeChannelResetCount','RuntimeChannelInputWaveformSHA256', ...
                'RuntimeChannelCanonicalInputSamples','RuntimeChannelInputSampleDomain', ...
                'RuntimeChannelOutputSampleAlignment','RuntimeChannelAppliedAlignmentTrimSamples', ...
                'RuntimeChannelAlignmentLookaheadSamples','RuntimeChannelObjectClockExact', ...
                'RuntimeChannelTransmitAndReceiveSwapped','RuntimeChannelElementExpansionApplied', ...
                'RuntimeChannelPathGainsSHA256','RuntimeChannelPathGainElementCount', ...
                'RuntimeChannelPathGainCapturePolicy','RuntimeChannelPathGainCaptureScope', ...
                'RuntimeChannelOutputWaveformSHA256'},'Execution');
            d=rp.ChannelSignalDependency; localDependency(d,obj.Binding);
            localFields(d,{'StartSample','EndSampleExclusive'},'Execution');
            names=fieldnames(obj.Dependency);
            for k=1:numel(names)
                name=names{k};
                assert(isfield(d,name)&&isequaln(d.(name),obj.Dependency.(name)), ...
                    'sixgr:channel:AppliedReferenceHistory', ...
                    'Dependency changed without an original retarget receipt: %s.',name);
            end
            assert(isa(originalInputChunk,'sixgr.phy.waveform.WaveformChunk') && ...
                isscalar(originalInputChunk),'sixgr:channel:AppliedReferenceInput', ...
                'Supply the original post-TX-RF aggregate input chunk.');
            localSamples(componentSamples,'Input'); localSamples(originalInputChunk.Samples,'Input');
            n=size(componentSamples,1);
            assert(n<flintmax-obj.NextSampleIndex, ...
                'sixgr:channel:AppliedReferenceClock','Interval exceeds the exact sample-clock range.');
            stop=obj.NextSampleIndex+n;
            assert(stop>obj.NextSampleIndex&&stop-obj.NextSampleIndex==n, ...
                'sixgr:channel:AppliedReferenceClock','Require exact nonzero sample-clock progression.');
            assert(isequal(size(componentSamples),size(originalInputChunk.Samples)) && ...
                size(componentSamples,2)==d.NumTxAnt && originalInputChunk.StartSample==obj.NextSampleIndex && ...
                originalInputChunk.EndSample+1==stop, ...
                'sixgr:channel:AppliedReferenceInput','Component and aggregate must share the exact physical support.');
            localInteger(stop,0,'Clock');
            if ~isempty(fieldnames(obj.ComponentBirth))
                % Source support ends before possible upstream PA/delay tails.
                % Only the zero pre-birth condition applies at channel input;
                % never clip channel input or output at the queued TX end.
                beforeBirth=obj.NextSampleIndex+(0:n-1).'<obj.ComponentBirth.ComponentSupportStartSample;
                assert(~any(componentSamples(beforeBirth,:)~=0,'all'), ...
                    'sixgr:channel:AppliedReferenceHistory','Component input precedes its declared source birth.');
            end
            assert(localLogical(rp.RuntimeChannelStateUsed,'Execution') && ...
                localLogical(rp.RuntimeChannelObjectClockExact,'Clock') && ...
                ~localLogical(rp.RuntimeChannelElementExpansionApplied,'Execution') && ...
                localText(rp.RuntimeChannelInputSampleDomain,'Execution')=="materialized_channel_ports" && ...
                localText(rp.RuntimeChannelStateKey,'Execution')==string(d.StateKey) && ...
                rp.RuntimeChannelResetCount==d.RuntimeResetCount && ...
                localLogical(rp.RuntimeChannelTransmitAndReceiveSwapped,'Execution')==d.NativeSwapped, ...
                'sixgr:channel:AppliedReferenceExecution','Require the original unremapped current-direction execution.');
            assert(isequal(rp.RuntimeChannelStartSample,obj.NextSampleIndex) && ...
                isequal(rp.RuntimeChannelEndSample,stop) && ...
                isequal(d.StartSample,obj.NextSampleIndex) && isequal(d.EndSampleExclusive,stop) && ...
                isequal(rp.RuntimeChannelCanonicalInputSamples,n) && ...
                localText(rp.RuntimeChannelOutputSampleAlignment,'Clock')=="continuous_raw_samples" && ...
                isequal(rp.RuntimeChannelAppliedAlignmentTrimSamples,0) && ...
                isequal(rp.RuntimeChannelAlignmentLookaheadSamples,0), ...
                'sixgr:channel:AppliedReferenceClock','No gaps, overlap, padding or trimming are allowed.');
            localReference(reference,d,obj.NextSampleIndex,stop,obj.ObjectTimeOffsetSamples);
            gainsHash=sixgr.phy.waveform.WaveformHash.runtimeArray(reference.PathGains);
            assert(localText(rp.RuntimeChannelPathGainCapturePolicy,'Reference')== ...
                "explicit_same_execution_full_channel_reference" && ...
                localText(rp.RuntimeChannelPathGainCaptureScope,'Reference')=="complete_executed_physical_interval" && ...
                isequal(rp.RuntimeChannelPathGainElementCount,numel(reference.PathGains)) && ...
                localHash(rp.RuntimeChannelPathGainsSHA256,'Reference')==gainsHash && ...
                localHash(rp.RuntimeChannelOutputWaveformSHA256,'Reference')== ...
                localHash(reference.OutputWaveformSHA256,'Reference'), ...
                'sixgr:channel:AppliedReferenceReference','Retain the original full gain tensor and native output binding.');
            % These two original serializations are intentionally distinct.
            % runtimeArray binds class+shape; WaveformChunk.SHA256 is numeric.
            aggregateHash=sixgr.phy.waveform.WaveformHash.runtimeArray(originalInputChunk.Samples);
            assert(localHash(rp.RuntimeChannelInputWaveformSHA256,'Input')==aggregateHash && ...
                localHash(reference.InputWaveformSHA256,'Input')==aggregateHash, ...
                'sixgr:channel:AppliedReferenceInput','Reference/replay do not bind the original aggregate samples.');
            normalization=[reference.NormalizePathGains reference.NormalizeChannelOutputs];
            assert(isempty(obj.Normalization)||isequal(obj.Normalization,normalization), ...
                'sixgr:channel:AppliedReferenceNormalization','Original normalization flags changed mid-installation.');
            loss=linkExecution.LossReplay;
            localFields(loss,{'AppliedLargeScaleAmplitudeGain','AppliedLargeScaleGain_dB', ...
                'SampleRate_Hz','PowerContextAmplitudeUnit','PowerContextDirection'},'Loss');
            gain=loss.AppliedLargeScaleAmplitudeGain; db=loss.AppliedLargeScaleGain_dB;
            assert(isa(gain,'double')&&isreal(gain)&&isscalar(gain)&&isfinite(gain)&&gain>0 && ...
                isa(db,'double')&&isreal(db)&&isscalar(db)&&isfinite(db) && ...
                isfinite(10^(db/20))&&10^(db/20)>0 && ...
                abs(gain-10^(db/20))<=32*eps(max(gain,10^(db/20))) && ...
                isequal(loss.SampleRate_Hz,d.SampleRateHz) && ...
                localText(loss.PowerContextAmplitudeUnit,'Loss')==obj.Binding.WaveformAmplitudeUnit && ...
                localText(loss.PowerContextDirection,'Loss')==string(d.Direction), ...
                'sixgr:channel:AppliedReferenceLoss','Retain the original consistent amplitude/dB loss operands.');
            [nativeSamples,newState]=sixgr.phy.waveform.applySampledFadingChannel( ...
                componentSamples,reference.PathFilters,reference.PathGains,obj.FilterState);
            desiredSamples=nativeSamples.*gain;
            assert(all(isfinite(nativeSamples),'all')&&all(isfinite(desiredSamples),'all'), ...
                'sixgr:channel:AppliedReferenceOverflow','Reference output overflowed.');
            next=obj; next.FilterState=newState; next.NextSampleIndex=stop;
            next.Normalization=normalization;
            receipt=struct('ContractVersion',"sixgr.channel.AppliedChannelReferenceStream/v1", ...
                'Source',"supplied_original_full_sample_channel_operator", ...
                'LinkID',obj.Binding.LinkID,'TX',obj.Binding.TX,'RX',obj.Binding.RX, ...
                'ConfigurationEpoch',obj.Binding.ConfigurationEpoch,'StateKey',string(d.StateKey), ...
                'Direction',string(d.Direction),'StartSample',obj.NextSampleIndex, ...
                'EndSampleExclusive',stop,'SampleRateHz',d.SampleRateHz, ...
                'ObjectTimeOffsetSamples',obj.ObjectTimeOffsetSamples, ...
                'ModelHistoryStartSample',obj.ModelHistoryStartSample, ...
                'ComponentBirth',obj.ComponentBirth,'OriginalBirthSnapshot',obj.OriginalBirthSnapshot, ...
                'ComponentHistoryAuthority',"independent_zero_model_FIR_not_original_aggregate_memory", ...
                'ComponentBirthAuthority',"caller_supplied_registration_not_original_owner_verified", ...
                'OriginalOwnerVerified',false,'SourceSupportEndAppliedAsTrim',false, ...
                'InputHistoryStartSample',d.InputHistoryStartSample,'NativeSwapped',d.NativeSwapped, ...
                'FilterSHA256',string(d.FilterSHA256),'NativeInitializationSHA256',string(d.NativeInitializationSHA256), ...
                'OriginalPathGainsSHA256',gainsHash, ...
                'OriginalNativeAggregateOutputSHA256',string(reference.OutputWaveformSHA256), ...
                'ComponentInputSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(componentSamples), ...
                'OriginalAggregateInputSHA256',aggregateHash, ...
                'OriginalInputChunkSHA256',originalInputChunk.SHA256, ...
                'InputHashSerialization',"WaveformHash.runtimeArray", ...
                'OriginalChunkHashSerialization',"WaveformHash.numeric", ...
                'NativeOutputSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(nativeSamples), ...
                'DesiredOutputSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(desiredSamples), ...
                'NativePlane',"channel_output_before_large_scale_loss", ...
                'DesiredPlane',"link_output_after_original_loss_before_RX_sum_noise_RF", ...
                'WaveformAmplitudeUnit',obj.Binding.WaveformAmplitudeUnit, ...
                'AppliedLargeScaleAmplitudeGain',gain,'LossApplicationCount',1, ...
                'ReferenceNormalizePathGains',reference.NormalizePathGains, ...
                'ReferenceNormalizeChannelOutputs',reference.NormalizeChannelOutputs, ...
                'NormalizationFlagsVerified',false, ...
                'NormalizationFlagsAuthority',"unverified_reference_metadata_not_used_for_scaling", ...
                'AdditionalNormalizationApplied',false,'AdditionalChannelExecutions',0, ...
                'ReceiverEstimatorInput',false,'SharedRuntimeIntegrationQualified',false, ...
                'EndpointBindingAuthority',"caller_supplied_original_link_wrapper", ...
                'PortAttributionQualified',false,'StandardizedPowerAccuracyQualified',false);
        end

        function next=retarget(obj,binding,dependency)
            % RF transmit/receive endpoint IDs can legitimately differ
            % (gnb versus gnb_rx). The caller supplies the original new
            % wrapper; this adapter does not infer aliases or establish
            % global radio-owner identity from changed endpoint names.
            assert(isempty(fieldnames(obj.ComponentBirth)), ...
                'sixgr:channel:AppliedReferenceHistory', ...
                'A born component cannot change physical TX/RX; its current-direction channel segment ends here.');
            binding=localBinding(binding); localDependency(dependency,binding);
            assert(binding.LinkID==obj.Binding.LinkID && ...
                binding.ConfigurationEpoch==obj.Binding.ConfigurationEpoch && ...
                binding.WaveformAmplitudeUnit==obj.Binding.WaveformAmplitudeUnit && ...
                binding.TX~=obj.Binding.TX && binding.RX~=obj.Binding.RX, ...
                'sixgr:channel:AppliedReferenceBinding','Retarget must retain the link/epoch/unit and change both endpoints.');
            d=dependency; old=obj.Dependency;
            assert(string(d.HistoryInitializationSource)=="original_native_direction_swap_filter_reset" && ...
                string(d.StateKey)==string(old.StateKey) && d.InputHistoryStartSample==obj.NextSampleIndex && ...
                string(d.Direction)~=string(old.Direction) && d.NativeSwapped~=old.NativeSwapped && ...
                d.RuntimeResetCount==old.RuntimeResetCount && d.SampleRateHz==old.SampleRateHz && ...
                d.NumTxAnt==old.NumRxAnt && d.NumRxAnt==old.NumTxAnt && ...
                string(d.NativeInitializationSHA256)==string(old.NativeInitializationSHA256), ...
                'sixgr:channel:AppliedReferenceHistory','Retarget requires the original same-clock native swap.');
            r=d.InitializationReceipt;
            localFields(r,{'Before','After','OriginalConsumedZeroTailSamples', ...
                'NativeSemantics','AdditionalChannelExecutions','ElapsedIdleTimeUsedAsReset'},'History');
            localInteger(r.OriginalConsumedZeroTailSamples,0,'History');
            assert(localText(r.NativeSemantics,'History')== ...
                "R2026a_nrCDLChannel_swapTransmitAndReceive_selected_FIR_and_batch_reset" && ...
                isequal(r.AdditionalChannelExecutions,0) && ...
                ~localLogical(r.ElapsedIdleTimeUsedAsReset,'History'), ...
                'sixgr:channel:AppliedReferenceHistory','Elapsed time is not native filter-reset evidence.');
            localSnapshot(r.Before,old,obj.NextSampleIndex);
            localSnapshot(r.After,d,obj.NextSampleIndex);
            assert(r.Before.TotalAppliedSamples==r.After.TotalAppliedSamples && ...
                r.Before.TotalObjectInputSamples==r.After.TotalObjectInputSamples && ...
                r.After.TotalObjectInputSamples==obj.NextSampleIndex+obj.ObjectTimeOffsetSamples, ...
                'sixgr:channel:AppliedReferenceHistory','Retarget must not advance physical/native time.');
            next=obj; next.Binding=binding; next.Dependency=d;
            next.ModelHistoryStartSample=d.InputHistoryStartSample;
            next.FilterState=complex(zeros(d.MemorySamples,d.NumTxAnt,d.FilterSize(2)));
        end
    end
    methods (Static)
        function obj=fromComponentBirth(binding,dependency,originalSnapshot,birth)
            % Reuse the fully validated construction path, never synthesize a
            % fresh native dependency, offset, or aggregate filter history.
            obj=sixgr.channel.AppliedChannelReferenceStream( ...
                binding,dependency,originalSnapshot,birth);
        end
    end
end

function localBirth(birth,d)
fields={'ContractVersion','ParentComponentID','ResourceID','LogicalPort', ...
    'ModelHistoryStartSample','ComponentSupportStartSample', ...
    'ComponentSupportEndSampleExclusive','RegistrationSHA256'};
localFields(birth,fields,'History');
assert(numel(fieldnames(birth))==numel(fields) && ...
    localText(birth.ContractVersion,'History')=="sixgr.rf.declared_TX_component_birth/v1", ...
    'sixgr:channel:AppliedReferenceHistory','Require the explicit declared TX-component birth contract.');
localText(birth.ParentComponentID,'History'); localText(birth.ResourceID,'History');
localInteger(birth.LogicalPort,0,'History'); localHash(birth.RegistrationSHA256,'History');
for name=["ModelHistoryStartSample","ComponentSupportStartSample","ComponentSupportEndSampleExclusive"]
    localInteger(birth.(name),0,'History');
end
assert(d.InputHistoryStartSample<=birth.ModelHistoryStartSample && ...
    birth.ModelHistoryStartSample<=birth.ComponentSupportStartSample && ...
    birth.ComponentSupportStartSample<birth.ComponentSupportEndSampleExclusive, ...
    'sixgr:channel:AppliedReferenceHistory','Require original history <= model start <= nonempty source support.');
end

function [offset,applied]=localHistoryOrigin(d)
r=d.InitializationReceipt;
switch localText(d.HistoryInitializationSource,'History')
    case "original_fresh_zero_warmup"
        localFields(r,{'CurrentSampleIndex','TotalAppliedSamples','TotalIdleAdvancedSamples', ...
            'WarmupSamples','ResetCount'},'History');
        for name=["CurrentSampleIndex","TotalAppliedSamples","TotalIdleAdvancedSamples", ...
                "WarmupSamples","ResetCount"]
            localInteger(r.(name),0,'History');
        end
        assert(r.CurrentSampleIndex==d.InputHistoryStartSample && ...
            r.TotalAppliedSamples==0 && r.ResetCount==d.RuntimeResetCount, ...
            'sixgr:channel:AppliedReferenceHistory','Fresh receipt does not describe this origin.');
        offset=r.WarmupSamples; applied=r.TotalAppliedSamples;
    case "original_native_direction_swap_filter_reset"
        localFields(r,{'Before','After','OriginalConsumedZeroTailSamples', ...
            'NativeSemantics','AdditionalChannelExecutions','ElapsedIdleTimeUsedAsReset'},'History');
        localInteger(r.OriginalConsumedZeroTailSamples,0,'History');
        assert(localText(r.NativeSemantics,'History')== ...
            "R2026a_nrCDLChannel_swapTransmitAndReceive_selected_FIR_and_batch_reset" && ...
            isequal(r.AdditionalChannelExecutions,0) && ...
            ~localLogical(r.ElapsedIdleTimeUsedAsReset,'History'), ...
            'sixgr:channel:AppliedReferenceHistory','Require the original native reset, not elapsed idle time.');
        localSnapshot(r.After,d,d.InputHistoryStartSample);
        old=d; old.NumTxAnt=d.NumRxAnt; old.NumRxAnt=d.NumTxAnt;
        old.NativeSwapped=~d.NativeSwapped;
        if string(d.Direction)=="DL", old.Direction="UL"; else, old.Direction="DL"; end
        % Validate the supplied ORIGINAL Before snapshot against the known
        % reciprocal relation; old is a comparison descriptor, not a receipt.
        localSnapshot(r.Before,old,d.InputHistoryStartSample);
        assert(r.Before.TotalAppliedSamples==r.After.TotalAppliedSamples && ...
            r.Before.TotalObjectInputSamples==r.After.TotalObjectInputSamples && ...
            r.After.TotalObjectInputSamples>=d.InputHistoryStartSample, ...
            'sixgr:channel:AppliedReferenceHistory','Original retarget must preserve physical/native counters.');
        offset=r.After.TotalObjectInputSamples-d.InputHistoryStartSample;
        applied=r.After.TotalAppliedSamples;
    otherwise
        error('sixgr:channel:AppliedReferenceHistory','Unsupported original channel history initialization.');
end
localInteger(offset,0,'History');
end

function b=localBinding(b)
localFields(b,{'LinkID','TX','RX','ConfigurationEpoch','WaveformAmplitudeUnit'},'Binding');
for name=["LinkID","TX","RX","WaveformAmplitudeUnit"]
    b.(name)=localText(b.(name),'Binding');
end
localInteger(b.ConfigurationEpoch,0,'Binding');
assert(b.TX~=b.RX && any(b.WaveformAmplitudeUnit== ...
    ["sqrt_mW","normalized_complex_baseband","input_amplitude"]), ...
    'sixgr:channel:AppliedReferenceBinding','Declare distinct endpoints and the original waveform unit.');
end

function localDependency(d,b)
localFields(d,{'ContractVersion','Available','Status','SampleRateHz','ConfigurationEpoch', ...
    'StateKey','Direction','NumTxAnt','NumRxAnt','RuntimeResetCount','MemorySamples', ...
    'InputHistoryStartSample','ZeroInputHistoryAtOrigin','HistoryInitializationSource', ...
    'FilterSHA256','NativeInitializationSHA256','NativeSwapped','FilterSize', ...
    'InitializationReceipt','NativeFilterAuthority','AdditionalChannelExecutions'},'Dependency');
assert(localText(d.ContractVersion,'Dependency')=="sixgr.channel.executed_signal_dependency/v1" && ...
    localLogical(d.Available,'Dependency') && ...
    localText(d.Status,'Dependency')=="available_original_native_finite_FIR_support" && ...
    localText(d.NativeFilterAuthority,'Dependency')=="R2026a_Inf_fresh_both_direction_public_getPathFilters" && ...
    localLogical(d.ZeroInputHistoryAtOrigin,'Dependency') && isequal(d.AdditionalChannelExecutions,0), ...
    'sixgr:channel:AppliedReferenceDependency','Require original supported native finite-FIR authority.');
localInteger(d.ConfigurationEpoch,0,'Dependency');
localInteger(d.NumTxAnt,1,'Dependency'); localInteger(d.NumRxAnt,1,'Dependency');
localInteger(d.RuntimeResetCount,0,'Dependency'); localInteger(d.MemorySamples,0,'Dependency');
localInteger(d.InputHistoryStartSample,0,'Dependency'); localLogical(d.NativeSwapped,'Dependency');
localText(d.StateKey,'Dependency'); localHash(d.FilterSHA256,'Dependency');
localHash(d.NativeInitializationSHA256,'Dependency');
assert(isa(d.SampleRateHz,'double')&&isreal(d.SampleRateHz)&&isscalar(d.SampleRateHz)&& ...
    isfinite(d.SampleRateHz)&&d.SampleRateHz>0 && ...
    any(localText(d.Direction,'Dependency')==["DL","UL"]) && ...
    d.ConfigurationEpoch==b.ConfigurationEpoch && ...
    isa(d.FilterSize,'double')&&isreal(d.FilterSize)&&isequal(size(d.FilterSize),[1 2]) && ...
    all(isfinite(d.FilterSize))&&all(d.FilterSize==fix(d.FilterSize))&&all(d.FilterSize>=1) && ...
    d.FilterSize(1)==d.MemorySamples+1, ...
    'sixgr:channel:AppliedReferenceDependency','Invalid original dependency dimensions, epoch or clock.');
end

function localReference(r,d,first,stop,offset)
assert(stop-1<flintmax-offset, ...
    'sixgr:channel:AppliedReferenceClock','Native object sample coordinates exceed the exact integer range.');
localFields(r,{'Source','StartSample','EndSampleExclusive','SampleRateHz','PathGains', ...
    'PathFilters','SampleTimes_s','NormalizeChannelOutputs','NormalizePathGains', ...
    'NumTransmitAntennas','NumReceiveAntennas','StateKey','AdditionalChannelExecutions', ...
    'ReceiverEstimatorInput','LargeScaleLossApplied','PhysicalPortMappingApplied','RFIncluded', ...
    'SampleTimeClockDomain','ObjectTimeOffsetSamples','OutputSampleAlignment', ...
    'AppliedAlignmentTrimSamples','AlignmentLookaheadSamples','CanonicalEndSampleExclusive', ...
    'InputWaveformSHA256','OutputWaveformSHA256'},'Reference');
assert(localText(r.Source,'Reference')=="same_executed_NR_channel_path_gains_and_filters" && ...
    localText(r.StateKey,'Reference')==string(d.StateKey) && ...
    isequal(r.NumTransmitAntennas,d.NumTxAnt)&&isequal(r.NumReceiveAntennas,d.NumRxAnt) && ...
    isequal(r.AdditionalChannelExecutions,0)&&~localLogical(r.ReceiverEstimatorInput,'Reference') && ...
    ~localLogical(r.LargeScaleLossApplied,'Reference')&&~localLogical(r.PhysicalPortMappingApplied,'Reference') && ...
    ~localLogical(r.RFIncluded,'Reference'), ...
    'sixgr:channel:AppliedReferenceReference','Require unmodified original native physical-basis coefficients.');
localLogical(r.NormalizeChannelOutputs,'Normalization'); localLogical(r.NormalizePathGains,'Normalization');
localSamples(r.PathFilters,'Reference');
assert(isreal(r.PathFilters)&&isequal(size(r.PathFilters),d.FilterSize) && ...
    sixgr.phy.waveform.WaveformHash.numeric(r.PathFilters)==string(d.FilterSHA256) && ...
    isa(r.PathGains,'double')&&~issparse(r.PathGains)&&~isa(r.PathGains,'gpuArray') && ...
    ndims(r.PathGains)<=4&&size(r.PathGains,1)==stop-first && ...
    size(r.PathGains,2)==d.FilterSize(2)&&size(r.PathGains,3)==d.NumTxAnt && ...
    size(r.PathGains,4)==d.NumRxAnt&&all(isfinite(r.PathGains),'all'), ...
    'sixgr:channel:AppliedReferenceReference','Full double per-sample gains and original filters are required.');
assert(isequal(r.StartSample,first)&&isequal(r.EndSampleExclusive,stop) && ...
    isequal(r.CanonicalEndSampleExclusive,stop)&&isequal(r.SampleRateHz,d.SampleRateHz) && ...
    isequal(r.ObjectTimeOffsetSamples,offset) && ...
    localText(r.SampleTimeClockDomain,'Clock')=="nr_channel_object_seconds" && ...
    localText(r.OutputSampleAlignment,'Clock')=="continuous_raw_samples" && ...
    isequal(r.AppliedAlignmentTrimSamples,0)&&isequal(r.AlignmentLookaheadSamples,0) && ...
    isa(r.SampleTimes_s,'double')&&isreal(r.SampleTimes_s) && ...
    isequal(size(r.SampleTimes_s),[stop-first 1])&&all(isfinite(r.SampleTimes_s)) && ...
    all(abs(r.SampleTimes_s*d.SampleRateHz-(offset+(first:stop-1).'))<1e-5), ...
    'sixgr:channel:AppliedReferenceClock','Retain original physical/native clocks and the complete interval.');
% Observation-specific copies may be complete, but an actual cropped
% execution is never allowed to stand in for missing stream history.
if isfield(r,'ExecutionStartSample')||isfield(r,'ExecutionEndSampleExclusive')
    localFields(r,{'ExecutionStartSample','ExecutionEndSampleExclusive'},'Clock');
    assert(isequal(r.ExecutionStartSample,first)&&isequal(r.ExecutionEndSampleExclusive,stop), ...
        'sixgr:channel:AppliedReferenceClock','Cropped execution references are not complete channel intervals.');
end
end

function localSnapshot(s,d,clock)
localFields(s,{'StateKey','Direction','CurrentSampleIndex','NumTxAnt','NumRxAnt', ...
    'ResetCount','TotalAppliedSamples','TotalObjectInputSamples','NativeSwapped'},'History');
for name=["CurrentSampleIndex","NumTxAnt","NumRxAnt","ResetCount", ...
        "TotalAppliedSamples","TotalObjectInputSamples"]
    localInteger(s.(name),0,'History');
end
assert(localText(s.StateKey,'History')==string(d.StateKey) && ...
    localText(s.Direction,'History')==string(d.Direction) && s.CurrentSampleIndex==clock && ...
    s.NumTxAnt==d.NumTxAnt&&s.NumRxAnt==d.NumRxAnt&&s.ResetCount==d.RuntimeResetCount && ...
    localLogical(s.NativeSwapped,'History')==d.NativeSwapped, ...
    'sixgr:channel:AppliedReferenceHistory','Native before/after snapshot does not bind the current stream.');
end

function localFields(v,names,scope)
assert(isstruct(v)&&isscalar(v)&&all(isfield(v,names)), ...
    ['sixgr:channel:AppliedReference' scope],'Missing or malformed original %s record.',scope);
end
function v=localText(v,scope)
assert((isstring(v)&&isscalar(v)&&~ismissing(v))||(ischar(v)&&isrow(v)), ...
    ['sixgr:channel:AppliedReference' scope],'Require scalar text.');
v=string(v);
assert(strlength(v)>0,['sixgr:channel:AppliedReference' scope],'Require nonempty original text.');
end
function v=localHash(v,scope)
v=localText(v,scope);
assert(~isempty(regexp(char(v),'^[0-9a-fA-F]{64}$','once')), ...
    ['sixgr:channel:AppliedReference' scope],'Require a complete original SHA-256.');
v=lower(v);
end
function v=localLogical(v,scope)
assert((islogical(v)||isnumeric(v))&&isreal(v)&&isscalar(v)&&isfinite(v)&&any(v==[0 1]), ...
    ['sixgr:channel:AppliedReference' scope],'Require a finite scalar logical value.');
v=logical(v);
end
function localInteger(v,minimum,scope)
assert(isa(v,'double')&&isreal(v)&&isscalar(v)&&isfinite(v)&&v==fix(v)&& ...
    v>=minimum&&v<flintmax,['sixgr:channel:AppliedReference' scope],'Require an exact nonnegative double index/count.');
end
function localSamples(v,scope)
assert(isa(v,'double')&&~isa(v,'gpuArray')&&~issparse(v)&&ismatrix(v)&& ...
    ~isempty(v)&&all(isfinite(v),'all'), ...
    ['sixgr:channel:AppliedReference' scope],'Require finite full CPU double samples.');
end
