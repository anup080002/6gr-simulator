classdef PiecewiseAWGNReference
    % Exact sample-indexed lab-operator evidence, not NR fading or RX Hest.
    % OperatorSegments and their signature cover the ORIGINAL processor
    % interval. StartSample/EndSampleExclusive and gains may be cropped.
    methods (Static)
        function hash=signature(segments)
            % Preserve the signature already produced by the physical owner.
            values=[];
            for k=1:numel(segments)
                s=segments(k); H=s.Matrix;
                values=[values;s.FirstOffset;s.EndOffsetExclusive; ... %#ok<AGROW>
                    double(s.EpisodeActive);size(H,1);size(H,2); ...
                    real(H(:));imag(H(:))];
            end
            hash=string(sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(values));
        end

        function tf=metadataValid(r)
            required={'Source','StartSample','EndSampleExclusive','SampleRateHz', ...
                'NumTransmitAntennas','NumReceiveAntennas','PathFilters', ...
                'SampleTimes_s','NormalizeChannelOutputs','NormalizePathGains', ...
                'ReceiverEstimatorInput','AdditionalChannelExecutions', ...
                'LargeScaleLossApplied','PhysicalPortMappingApplied','RFIncluded', ...
                'OperatorExecutionStartSample','OperatorExecutionEndSampleExclusive', ...
                'OperatorSegments','AppliedAWGNSpatialMatrixSHA256', ...
                'BeamFailureRecoveryEpisodeActive','BeamFailureRecoverySegmentCount','StateKey'};
            tf=isstruct(r) && isscalar(r) && all(isfield(r,required));
            if ~tf, return; end
            tf=localText(r.Source) && isequal(string(r.Source),"executed_piecewise_matrix_AWGN_operator") && ...
                ~isfield(r,'SpatialMatrix') && ...
                localText(r.StateKey) && ...
                localInteger(r.NumTransmitAntennas,1) && localInteger(r.NumReceiveAntennas,1) && ...
                localInteger(r.StartSample,0) && localInteger(r.EndSampleExclusive,1) && ...
                localInteger(r.OperatorExecutionStartSample,0) && ...
                localInteger(r.OperatorExecutionEndSampleExclusive,1) && ...
                r.OperatorExecutionStartSample<=r.StartSample && ...
                r.StartSample<r.EndSampleExclusive && ...
                r.EndSampleExclusive<=r.OperatorExecutionEndSampleExclusive && ...
                isnumeric(r.SampleRateHz) && isreal(r.SampleRateHz) && ...
                isscalar(r.SampleRateHz) && isfinite(r.SampleRateHz) && r.SampleRateHz>0 && ...
                isequal(r.PathFilters,1) && isequal(r.NormalizeChannelOutputs,false) && ...
                isequal(r.NormalizePathGains,false) && isequal(r.ReceiverEstimatorInput,false) && ...
                isequal(r.AdditionalChannelExecutions,0) && isequal(r.RFIncluded,false) && ...
                isequal(r.LargeScaleLossApplied,false) && isequal(r.PhysicalPortMappingApplied,false);
            if ~tf, return; end
            ns=r.EndSampleExclusive-r.StartSample;
            tf=isnumeric(r.SampleTimes_s) && isreal(r.SampleTimes_s) && ...
                isequal(size(r.SampleTimes_s),[ns 1]) && ...
                isequal(r.SampleTimes_s,(r.StartSample+(0:ns-1)')/r.SampleRateHz);
            s=r.OperatorSegments;
            tf=tf && isstruct(s) && ~isempty(s) && isvector(s) && ...
                all(isfield(s,{'FirstOffset','EndOffsetExclusive','EpisodeActive','Matrix','MatrixSHA256'}));
            if ~tf, return; end
            next=0;
            for k=1:numel(s)
                H=s(k).Matrix;
                tf=localInteger(s(k).FirstOffset,0) && ...
                    localInteger(s(k).EndOffsetExclusive,1) && ...
                    s(k).FirstOffset==next && s(k).EndOffsetExclusive>next && ...
                    islogical(s(k).EpisodeActive) && isscalar(s(k).EpisodeActive) && ...
                    isfloat(H) && isequal(size(H),[r.NumReceiveAntennas r.NumTransmitAntennas]) && ...
                    all(isfinite(H),'all') && ...
                    localText(s(k).MatrixSHA256) && ...
                    isequal(string(s(k).MatrixSHA256),string( ...
                    sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(H)));
                if ~tf, return; end
                next=s(k).EndOffsetExclusive;
            end
            tf=next==r.OperatorExecutionEndSampleExclusive-r.OperatorExecutionStartSample && ...
                isequal(r.BeamFailureRecoverySegmentCount,numel(s)) && ...
                isequal(r.BeamFailureRecoveryEpisodeActive,any([s.EpisodeActive])) && ...
                localText(r.AppliedAWGNSpatialMatrixSHA256) && ...
                isequal(string(r.AppliedAWGNSpatialMatrixSHA256), ...
                    sixgr.channel.PiecewiseAWGNReference.signature(s));
        end

        function tf=blockValid(r,piece,indices)
            % Metadata is checked once by the caller, including streamed
            % readers. Bound temporary comparisons to the supplied block.
            tf=iscell(indices) && isvector(indices) && numel(indices)>=1 && numel(indices)<=4;
            if ~tf, return; end
            indices(end+1:4)={1};
            dims=[r.EndSampleExclusive-r.StartSample 1 ...
                r.NumTransmitAntennas r.NumReceiveAntennas];
            tf=numel(indices)==4 && isfloat(piece) && ndims(piece)<=4 && all(isfinite(piece),'all');
            if ~tf, return; end
            for d=1:4
                ix=indices{d};
                tf=isnumeric(ix) && isvector(ix) && ~isempty(ix) && ...
                    all(isfinite(ix)) && all(ix==fix(ix)) && ...
                    all(ix>=1 & ix<=dims(d)) && numel(unique(ix))==numel(ix) && ...
                    size(piece,d)==numel(ix);
                if ~tf, return; end
            end
            times=r.StartSample+indices{1}(:)-1;
            covered=false(numel(times),1);
            for s=reshape(r.OperatorSegments,1,[])
                use=times>=r.OperatorExecutionStartSample+s.FirstOffset & ...
                    times<r.OperatorExecutionStartSample+s.EndOffsetExclusive;
                H=s.Matrix(indices{4},indices{3}).';
                expected=reshape(H,[1 1 numel(indices{3}) numel(indices{4})]);
                if any(use) && ~all(piece(use,:,:,:)==expected,'all')
                    tf=false; return;
                end
                covered=covered|use;
            end
            tf=all(covered);
        end

        function tf=matchesReplay(r,replay)
            % This joins the full processor signature, not a cropped hash.
            tf=all(isfield(r,{'ExecutionStartSample','ExecutionEndSampleExclusive'})) && ...
                all(isfield(replay,{'AppliedAWGNSpatialMatrixSHA256', ...
                'RuntimeChannelStartSample','RuntimeChannelEndSample', ...
                'RuntimeChannelStateKey','BeamFailureRecoveryEpisodeActive', ...
                'BeamFailureRecoverySegmentCount'})) && ...
                r.OperatorExecutionStartSample==r.ExecutionStartSample && ...
                r.OperatorExecutionEndSampleExclusive==r.ExecutionEndSampleExclusive && ...
                r.OperatorExecutionStartSample==replay.RuntimeChannelStartSample && ...
                r.OperatorExecutionEndSampleExclusive==replay.RuntimeChannelEndSample && ...
                string(r.StateKey)==string(replay.RuntimeChannelStateKey) && ...
                string(r.AppliedAWGNSpatialMatrixSHA256)==string(replay.AppliedAWGNSpatialMatrixSHA256) && ...
                isequal(r.BeamFailureRecoveryEpisodeActive,replay.BeamFailureRecoveryEpisodeActive) && ...
                isequal(r.BeamFailureRecoverySegmentCount,replay.BeamFailureRecoverySegmentCount);
        end
    end
end

function tf=localInteger(x,minimum)
tf=isnumeric(x) && isreal(x) && isscalar(x) && isfinite(x) && x>=minimum && x==fix(x);
end

function tf=localText(x)
tf=((isstring(x) && isscalar(x)) || (ischar(x) && isrow(x))) && ...
    ~ismissing(string(x)) && strlength(string(x))>0;
end
