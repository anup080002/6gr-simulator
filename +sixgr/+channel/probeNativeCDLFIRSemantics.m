function evidence=probeNativeCDLFIRSemantics(initialized,prototype)
%PROBENATIVECDLFIRSEMANTICS Observe native behavior on isolated channel copies.
% No original physical input or channel owner is executed or reset here.
% The private seeded probe is a capability check, not a simulation observation.
id='sixgr:channel:NativeFIRCapability';
assert(isa(initialized,'nrCDLChannel')&&isLocked(initialized)&& ...
    isinf(initialized.SampleDensity)&& ...
    string(initialized.RandomStream)=="mt19937ar with seed",id, ...
    'Require an initialized private-seeded per-sample CDL with explicit output normalization.');
contract=sixgr.channel.waveformChannelOutputContract(initialized);
assert(contract.OutputCount==3,id,'The native full-response signature must retain snapshot times.');
validateattributes(prototype,{'double','single'},{'2d','nonempty','finite'});
originalRNG=rng;
originalDirection=initialized.TransmitAndReceiveSwapped;
originalSeed=initialized.Seed; originalOrigin=initialized.InitialTime;
originalFilters=getPathFilters(initialized);
probe=clone(initialized);
% The source is at its fresh reset boundary. The cloned owner starts there;
% its deterministic stimuli and snapshots never enter the practical receiver.
state=[]; checks=cell(1,6); applied=0;
for k=1:6
    if any(k==[3 5])
        swapTransmitAndReceive(probe);
        state=[]; % This candidate semantic is verified by native output below.
    end
    nativeInfo=info(probe); filters=getPathFilters(probe);
    n=2*size(filters,1)+17; nt=double(nativeInfo.NumInputSignals);
    phase=((1:n).'+(k-1)*n)*(1:nt);
    x=cast(complex(sin(phase*.173),cos(phase*.271)),'like',prototype);
    if isempty(state),state=complex(zeros(size(filters,1)-1,nt,size(filters,2)));end
    [actual,gains,times]=sixgr.channel.applyWaveformChannelOnce(probe,x,true);
    assert(size(gains,1)==n&&isequal(size(times),[n 1])&& ...
        all(abs(times*probe.SampleRate-(probe.InitialTime*probe.SampleRate+applied+(0:n-1).'))<1e-5),id, ...
        'Probe requires original complete per-sample coefficients and native time progression.');
    [expected,state]=sixgr.phy.waveform.applySampledFadingChannel(x,filters,gains,state);
    % The original native path gains already carry the native gain scaling.
    % Verify the exported operator directly; never normalize it a second time.
    denominator=max([norm(double(actual),'fro'),norm(expected,'fro'),realmin]);
    relativeError=norm(double(actual)-expected,'fro')/denominator;
    bound=128*double(eps(class(prototype)))*max([size(gains,2),nt,1]);
    assert(isfinite(relativeError)&&relativeError<=bound,id, ...
        'Native FIR continuation/direction-reset arithmetic differs from the declared operator.');
    checks{k}=struct('Stage',k,'Swapped',logical(probe.TransmitAndReceiveSwapped), ...
        'Samples',n,'NumInputSignals',nt,'NumPaths',size(gains,2),'FilterSHA256', ...
        string(sixgr.phy.waveform.WaveformHash.numeric(filters)), ...
        'NativeOutputSHA256',string(sixgr.phy.waveform.WaveformHash.runtimeArray(actual)), ...
        'RelativeError',relativeError,'RelativeRoundoffBound',bound);
    applied=applied+n;
end
% Native clone/save continuation must preserve the same original future call.
copy=clone(probe);
snapshotPath=[tempname '.mat']; cleanup=onCleanup(@()localDelete(snapshotPath));
save(snapshotPath,'probe'); recovered=load(snapshotPath,'probe');
nativeInfo=info(probe); n=2*size(getPathFilters(probe),1)+19;
phase=(1:n).'*(1:double(nativeInfo.NumInputSignals));
x=cast(complex(cos(phase*.117),sin(phase*.213)),'like',prototype);
[a,ag,at]=sixgr.channel.applyWaveformChannelOnce(probe,x,true);
[b,bg,bt]=sixgr.channel.applyWaveformChannelOnce(copy,x,true);
[c,cg,ct]=sixgr.channel.applyWaveformChannelOnce(recovered.probe,x,true);
assert(isequal(a,b,c)&&isequal(ag,bg,cg)&&isequal(at,bt,ct),id, ...
    'Native clone/save/load must preserve exact continuation for this installation.');
assert(isequal(rng,originalRNG)&&initialized.TransmitAndReceiveSwapped==originalDirection&& ...
    initialized.Seed==originalSeed&&initialized.InitialTime==originalOrigin&& ...
    isequal(getPathFilters(initialized),originalFilters),id, ...
    'Isolated capability checks must not alter the original owner or global RNG.');
toolbox=ver('5g');
evidence=struct('ContractVersion',"sixgr.native_CDL_FIR_capability/v1", ...
    'Passed',true,'RuntimeMATLABRelease',string(version('-release')), ...
    'RuntimeMATLABVersion',string(version), ...
    'RuntimeToolboxVersion',string(toolbox.Version), ...
    'Source',"isolated_private_seeded_native_clone_public_API_probe", ...
    'FilterRule',"original_public_getPathFilters_samplewise_gains", ...
    'SwapRule',"selected_FIR_reset_no_physical_time_advance", ...
    'Checks',{checks},'ExactCloneContinuation',true,'ExactSaveLoadContinuation',true, ...
    'ProbeChannelExecutions',9,'OriginalOwnerChannelExecutions',0, ...
    'OriginalPhysicalSamplesAdvanced',0,'GlobalRNGUnchanged',true, ...
    'SampleDensity',Inf,'SampleClass',string(class(prototype)), ...
    'SampleRateHz',double(initialized.SampleRate), ...
    'Seed',double(initialized.Seed),'InitialTime_s',double(initialized.InitialTime), ...
    'OriginalDirectionSwapped',logical(originalDirection), ...
    'NormalizeChannelOutputs',logical(initialized.NormalizeChannelOutputs), ...
    'MeasurementOrAccuracyQualification',false);
end

