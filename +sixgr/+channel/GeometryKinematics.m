function state = GeometryKinematics(txPosition_m, rxPosition_m, ...
    txVelocity_mps, rxVelocity_mps, fc_Hz, dt_s)
%GEOMETRYKINEMATICS Observed link geometry and signed Doppler state.

arguments
    txPosition_m (1,3) double {mustBeFinite}
    rxPosition_m (1,3) double {mustBeFinite}
    txVelocity_mps (1,3) double {mustBeFinite}
    rxVelocity_mps (1,3) double {mustBeFinite}
    fc_Hz (1,1) double {mustBeFinite,mustBePositive}
    dt_s (1,1) double {mustBeFinite,mustBeNonnegative}
end

c = 299792458;
delta = rxPosition_m - txPosition_m;
distance3D = norm(delta);
if distance3D <= 0
    error("CHANNEL:InvalidGeometry", ...
        "Transmitter and receiver positions must be distinct.");
end
unitVector = delta ./ distance3D;
rangeRate = dot(rxVelocity_mps - txVelocity_mps, unitVector);
doppler = -rangeRate .* fc_Hz ./ c;

state = struct( ...
    "Distance2D_m", norm(delta(1:2)), ...
    "Distance3D_m", distance3D, ...
    "UnitVector", unitVector, ...
    "RangeRate_mps", rangeRate, ...
    "SignedDoppler_Hz", doppler, ...
    "PropagationDelay_s", distance3D ./ c, ...
    "PhaseIncrement_rad", 2 .* pi .* doppler .* dt_s, ...
    "CoordinateFrame", "global_cartesian_enu", ...
    "ProvenanceClass", "observed_runtime_geometry");
end
