function path=resolveRunArtifactPath(root,relative)
% Resolve existing run evidence, including its explicitly owned archive route.
% A junction by itself is not evidence of ownership. External storage is
% allowed only for flat channel MAT files with a matching relocation receipt.
arguments
    root {mustBeTextScalar}
    relative {mustBeTextScalar}
end
root=sixgr.util.canonicalPath(root);
relative=replace(string(relative),'\','/');
assert(isfolder(root) && ~ismissing(relative) && strlength(relative)>0 && ...
    isempty(regexp(char(relative),'(^/|^[A-Za-z]:|(^|/)\.\.?(/|$))','once')), ...
    'sixgr:util:RunArtifactPath','Use a non-traversing relative artifact path.');
path=string(java.io.File(char(fullfile(root,relative))).getCanonicalPath());
assert(isfile(path),'sixgr:util:RunArtifactMissing','Artifact does not exist: %s.',path);
realRoot=localReal(root); realPath=localReal(path);
receiptPath=fullfile(root,'meta','channel_archive_storage.json');
isArchive=startsWith(relative,"channel/mat/");
if isArchive && isfile(receiptPath)
    record=jsondecode(fileread(receiptPath));
    required={'Contract','Status','RunFolder','LogicalRelativeFolder', ...
        'ExternalFolder','ScientificDataChanged','SourceCodeMoved'};
    assert(all(isfield(record,required)) && ...
        string(record.Contract)=="LLSExternalChannelArchive/v1" && ...
        string(record.Status)=="verified" && ...
        strcmpi(sixgr.util.canonicalPath(record.RunFolder),root) && ...
        string(record.LogicalRelativeFolder)=="channel/mat" && ...
        isequal(record.ScientificDataChanged,false) && isequal(record.SourceCodeMoved,false), ...
        'sixgr:util:RunArtifactOwnership','Invalid external channel archive receipt.');
    name=extractAfter(relative,"channel/mat/");
    external=sixgr.util.canonicalPath(record.ExternalFolder);
    assert(ispc && ~contains(name,"/") && endsWith(name,".mat") && ...
        strlength(external)>3 && isfolder(external), ...
        'sixgr:util:RunArtifactOwnership','Only flat MAT files may use the declared external route.');
    realExternal=localReal(external);
    assert(~localWithin(realExternal,realRoot) && ~localWithin(realRoot,realExternal) && ...
        ~strcmpi(realRoot,realExternal) && ...
        java.nio.file.Files.isSameFile(java.io.File(char(fullfile(root,'channel','mat'))).toPath(), ...
            java.io.File(char(external)).toPath()) && ...
        localWithin(realPath,realExternal) && ...
        ~java.nio.file.Files.isSymbolicLink(java.io.File(char(fullfile(external,name))).toPath()) && ...
        java.nio.file.Files.isSameFile(java.io.File(char(path)).toPath(), ...
            java.io.File(char(fullfile(external,name))).toPath()), ...
        'sixgr:util:RunArtifactOwnership','Artifact route differs from its declared storage owner.');
else
    assert(localWithin(realPath,realRoot),'sixgr:util:RunArtifactOwnership', ...
        'Artifact leaves its run without an explicitly verified channel archive route.');
end
end

function path=localReal(path)
options=javaArray('java.nio.file.LinkOption',0);
path=string(java.io.File(char(path)).toPath().toRealPath(options).toString());
end

function yes=localWithin(path,root)
yes=startsWith(path,root+filesep,'IgnoreCase',ispc);
end
