function tf = localColumnHasRuntimeContent(col)
if isnumeric(col)
    tf = any(isfinite(double(col)));
    return;
end

if islogical(col)
    tf = true;
    return;
end

try
    vals = string(col);
catch
    tf = true;
    return;
end

normalized = lower(strtrim(fillmissing(vals, "constant", "")));
mask = strlength(normalized) > 0 ...
    & normalized ~= "nan" ...
    & normalized ~= "nat" ...
    & normalized ~= "<missing>" ...
    & normalized ~= "not_applicable";
if ~any(mask)
    tf = false;
    return;
end

inactivePrefixes = [ ...
    "not_recorded_by_active_", ...
    "not_emitted_by_active_", ...
    "field_not_emitted_by_active_", ...
    "not_applicable_for_active_"];
uniqueVals = unique(normalized(mask), "stable");
tf = ~all(arrayfun(@(token) any(startsWith(token, inactivePrefixes)), uniqueVals));
end
