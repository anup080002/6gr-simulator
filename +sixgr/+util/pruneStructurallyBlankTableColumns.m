function tf = localHasEvidenceCompanion(name, allNames)
base = string(name);
names = string(allNames(:));
if isempty(names)
    tf = false;
    return;
end
suffixes = ["_dB","_dBm","_Hz","_samples","_s","_ms","_bits","_Mbps","_dBHz"];
if ~any(endsWith(base, suffixes, "IgnoreCase", true))
    tf = false;
    return;
end
stem = regexprep(base, "(_dBm|_dBHz|_dB|_Hz|_samples|_s|_ms|_bits|_Mbps)$", "", "ignorecase");
companions = [stem + "Source"; stem + "ValueSource"; stem + "Status"; ...
    stem + "ValueStatus"; stem + "ValueRole"; stem + "NAReason"; ...
    stem + "Reason"; stem + "Availability"];
tf = any(ismember(lower(companions), lower(names)));
end

function tf = localColumnHasRuntimeContent(col)
if isnumeric(col)
    tf = any(isfinite(double(col)));
    return;
end

if islogical(col)
    tf = true;
    return;
end

try
    vals = string(col);
catch
    tf = true;
    return;
end

normalized = lower(strtrim(fillmissing(vals, "constant", "")));
mask = strlength(normalized) > 0 ...
    & normalized ~= "nan" ...
    & normalized ~= "nat" ...
    & normalized ~= "<missing>" ...
    & normalized ~= "not_applicable";
if ~any(mask)
    tf = false;
    return;
end

inactivePrefixes = [ ...
    "not_recorded_by_active_", ...
    "not_emitted_by_active_", ...
    "field_not_emitted_by_active_", ...
    "not_applicable_for_active_"];
uniqueVals = unique(normalized(mask), "stable");
tf = ~all(arrayfun(@(token) any(startsWith(token, inactivePrefixes)), uniqueVals));
end
