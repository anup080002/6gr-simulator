function T = pruneStructurallyBlankTableColumns(T)
%PRUNESTRUCTURALLYBLANKTABLECOLUMNS Drop columns with no runtime evidence.
%
% This is intentionally conservative: it never fills missing values and it
% preserves false-only logical flags because those can be real evidence that
% a condition did not occur. Empty tables keep their schema so explicitly
% empty primary artifacts remain self-describing.

if ~(istable(T) && ~isempty(T))
    return;
end

keepMask = false(1, width(T));
names = string(T.Properties.VariableNames);
for i = 1:numel(names)
    keepMask(i) = localIsContractEvidenceColumn(names(i)) ...
        || localColumnHasRuntimeContent(T.(char(names(i))));
end

if any(~keepMask)
    T(:, ~keepMask) = [];
end
end

function tf = localIsContractEvidenceColumn(name)
normalized = lower(strtrim(string(name)));
exactKeep = lower([ ...
    "NoiseVar", ...
    "NoiseVarStatus", ...
    "NoiseVarSource", ...
    "SNRConsistencyStatus", ...
    "ReceiverUsable", ...
    "DecodeAttempted", ...
    "DecodeUsable", ...
    "SINRValueRole", ...
    "AppliedPrecoderPMI", ...
    "AppliedBeamIndexSet", ...
    "BeamIndexSetMaterialized", ...
    "MeasurementRSRP_dB", ...
    "MeasurementRSRQ_dB", ...
    "MeasurementRSSI_dBm", ...
    "MeasurementUsable", ...
    "RuntimeMaterializationStatus", ...
    "RuntimeEvidenceStatus", ...
    "TimingEstimateAvailability", ...
    "CFOEstimateAvailability", ...
    "CorrectionLoopStatus", ...
    "TimingOffsetSamplesRaw", ...
    "TimingOffsetSamplesApplied", ...
    "CQI", ...
    "CQIDerivedMCS", ...
    "CalibrationProfile", ...
    "PBCHCRC", ...
    "MIBRecovered", ...
    "CRCOutcome", ...
    "DCIPayloadBits"]);
if any(normalized == exactKeep)
    tf = true;
    return;
end
tf = false;
end

function tf = localColumnHasRuntimeContent(col)
if isnumeric(col)
    tf = any(isfinite(double(col)));
    return;
end

if islogical(col)
    tf = true;
    return;
end

try
    vals = string(col);
catch
    tf = true;
    return;
end

normalized = lower(strtrim(fillmissing(vals, "constant", "")));
mask = strlength(normalized) > 0 ...
    & normalized ~= "nan" ...
    & normalized ~= "nat" ...
    & normalized ~= "<missing>" ...
    & normalized ~= "not_applicable";
if ~any(mask)
    tf = false;
    return;
end

inactivePrefixes = [ ...
    "not_recorded_by_active_", ...
    "not_emitted_by_active_", ...
    "field_not_emitted_by_active_", ...
    "not_applicable_for_active_"];
uniqueVals = unique(normalized(mask), "stable");
tf = ~all(arrayfun(@(token) any(startsWith(token, inactivePrefixes)), uniqueVals));
end
