function T = pruneStructurallyBlankTableColumns(T)
%PRUNESTRUCTURALLYBLANKTABLECOLUMNS Drop columns with no runtime evidence.
%
% This is intentionally conservative: it never fills missing values and it
% preserves false-only logical flags because those can be real evidence that
% a condition did not occur. Empty tables keep their schema so explicitly
% empty primary artifacts remain self-describing.

if ~(istable(T) && ~isempty(T))
    return;
end

keepMask = false(1, width(T));
names = string(T.Properties.VariableNames);
for i = 1:numel(names)
    keepMask(i) = localIsContractEvidenceColumn(names(i)) ...
        || localColumnHasRuntimeContent(T.(char(names(i))));
end

if any(~keepMask)
    T(:, ~keepMask) = [];
end
end

