classdef ReportBuilder
    %REPORTBUILDER Markdown/HTML status report without unsupported claims.

    methods (Static)
        function paths=write(runFolder,campaign,scenarioStatus,figures,manifest,tables)
            reportDir=fullfile(runFolder,"reports");sixgr.util.ensureFolder(reportDir);
            md=fullfile(reportDir,"campaign_report.md");html=fullfile(reportDir,"campaign_report.html");
            lines=["# BWOP AI 10.5.1.3 campaign report";""; ...
                "## 1. Executive summary";""; ...
                "- Run mode: `"+campaign.Mode+"`"; ...
                "- Configuration hash: `"+campaign.ConfigHash+"`"; ...
                "- Source document available: `"+string(campaign.SourceAvailable)+"`"; ...
                "- Analytical scenarios passed: `"+string(nnz(startsWith(scenarioStatus.ScenarioID,"ANA-")&scenarioStatus.Status=="PASS"))+"/7`"; ...
                "- Figure contract: `"+string(nnz(figures.Status=="PASS"))+" PASS, "+ ...
                string(nnz(figures.Status=="BLOCKED"))+" BLOCKED / 34`"; ...
                "- TDoc-ready measured figures: `"+string(manifest.tdoc_ready_measured_figures)+"`"; ...
                "- Placeholder curves generated: `false`"; ...
                "- This bounded engineering campaign validates execution and evidence generation; its low trial count is not a performance claim.";""];
            lines(end+1:end+6)=["## 2. Source document and revision";""; ...
                "- Document: `"+string(campaign.Config.source.controlling_document)+"`"; ...
                "- Revision: `"+string(campaign.Config.source.revision)+"`"; ...
                "- Available during execution: `"+string(campaign.SourceAvailable)+"`"; ...
                "- Values described as source-reported are provenance-bound to the supplied prompt until the document is supplied."];
            if ~campaign.SourceAvailable
                lines(end+1:end+3)=["";"### Source-document blocker"; ...
                    "The controlling DOCX was unavailable. Source-reported numerical baselines from the supplied prompt are retained with explicit provenance; no document-specific value was invented or presented as an independent extraction."];
            end
            lines(end+1:end+5)=["";"## 3. Repository/environment audit";""; ...
                "- Audit: [`repository_audit.md`](../metadata/repository_audit.md)."; ...
                "- Environment: [`environment.json`](../metadata/environment.json)."];
            lines(end+1:end+3)=["";"## 4. Scenario inventory and completion status";""];
            for i=1:height(scenarioStatus)
                lines(end+1)="- **"+scenarioStatus.Status(i)+"** `"+scenarioStatus.ScenarioID(i)+"` — "+scenarioStatus.Detail(i); %#ok<AGROW>
            end
            lines=[lines;localEvidenceSections(tables,campaign,manifest)];
            lines(end+1:end+3)=["";"## 18. Outputs still requiring calibration";""];
            blocked=figures(figures.Status=="BLOCKED",:);
            if isempty(blocked)
                lines(end+1)="None.";
            else
                for i=1:height(blocked)
                    lines(end+1)="- `"+blocked.FigureID(i)+"`: "+blocked.BlockerReason(i); %#ok<AGROW>
                end
            end
            lines(end+1:end+19)=["";"## 19. Recommended TDoc figure replacements";""; ...
                "- Use `F01`–`F09` only as clearly labelled procedure/analytical schematics."; ...
                "- Bounded measured `R01`, `R02`, `R05`–`R07`, and `R15` may illustrate the executed chain, but require publication-scale reruns before numerical performance claims."; ...
                "- Do not automatically alter existing TDoc Observations or Proposals.";""; ...
                "## 20. Open questions";""; ...
                "- RAN2: Which existing message carries early bandwidth capability, and what is the fallback state when it is absent or ambiguous?"; ...
                "- RAN4: What mandatory single-RF span and preparation-time classes apply before capability is known?"; ...
                "- AI 10.5.2.1: Which post-IA activation reference and bounded overlap/early-cease rule are normative candidates?";""; ...
                "## Interpretation constraints";""; ...
                "- `N_S` is a schedulable SIB1-PDSCH reference bandwidth; it is not actual allocation `A`."; ...
                "- Wider `N_S` with unchanged `A`, placement, MCS, symbols and power is not a PDSCH gain claim."; ...
                "- Procedure models using configured probabilities are not promoted into TDoc-ready measured results without calibrated LLS lookup provenance."; ...
                "- This campaign does not add connected-mode BWP or multi-carrier operation."];
            sixgr.util.writeTextFile(md,strjoin(lines,newline));
            escaped=replace(replace(replace(strjoin(lines,newline),"&","&amp;"),"<","&lt;"),">","&gt;");
            sixgr.util.writeTextFile(html,"<!doctype html><html><head><meta charset='utf-8'><title>BWOP AI10513</title>"+ ...
                "<style>body{font-family:Segoe UI,Arial;max-width:1100px;margin:2rem auto;white-space:pre-wrap;color:#102a2a}</style>"+ ...
                "</head><body>"+escaped+"</body></html>");
            calibration=fullfile(reportDir,"calibration_report.md");
            sixgr.util.writeTextFile(calibration,localCalibration(campaign,scenarioStatus));
            failures=fullfile(reportDir,"failures.md");
            sixgr.util.writeTextFile(failures,localFailures(blocked));
            paths=struct("Markdown",string(md),"HTML",string(html), ...
                "Calibration",string(calibration),"Failures",string(failures));
            %#ok<NASGU> tables is retained for future section-specific report expansion.
        end
    end
end

