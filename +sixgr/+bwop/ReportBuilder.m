function text=localCalibration(campaign,status)
text="# Calibration report"+newline+newline+ ...
    "- Source document available: `"+string(campaign.SourceAvailable)+"`"+newline+ ...
    "- CAL-001 status: `"+status.Status(status.ScenarioID=="CAL-001")+"`"+newline+ ...
    "- CAL-002 status: `"+status.Status(status.ScenarioID=="CAL-002")+"`"+newline+newline+ ...
    "Measured waveform curves remain separate from analytical/source arithmetic and retain their configured statistical class."+newline;
end

function text=localFailures(blocked)
text="# Blockers and failures"+newline+newline;
if isempty(blocked),text=text+"No blocked figure contract entry."+newline;return;end
for i=1:height(blocked),text=text+"- `"+blocked.FigureID(i)+"`: "+blocked.BlockerReason(i)+newline;end
end
