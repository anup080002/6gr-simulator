classdef ReceivedDLHARQCodingHistory
    % Immutable original coding identity derived at the UE from received DCI.
    % No transmitter bits, plans, grants or decode verdicts enter this object.
    properties (SetAccess=immutable)
        InitialAssignment
        UEId
        TBSBits
        InitialTargetCodeRate
        BaseGraph
        CombineSignature
    end
    methods
        function obj=ReceivedDLHARQCodingHistory(installed,a,ueId)
            validateattributes(ueId,{'numeric'},{'scalar','integer','positive','finite'});
            c=sixgr.phy.pdcch.validateConnectedAssignment(installed,a);
            assert(a.Direction=="DL" && c.Data.RNTIType=="C-RNTI" && ~a.RequiresHARQHistory, ...
                'sixgr:pdsch:ReceivedDLHARQHistoryRequired', ...
                'Original UE coding history requires received C-RNTI DL control with a defined new-TB MCS.');
            allocation=sixgr.phy.pdcch.connectedDataAllocation(installed,a);
            plan=sixgr.pdsch.DLSCHCodingPlan.resolve( ...
                'TransportBlockSize',allocation.NominalTBSBits,'TargetCodeRate',a.TargetCodeRate, ...
                'RateMatchedBitCount',allocation.RateMatchedCapacityBits,'RV',a.RV, ...
                'Modulation',a.Modulation,'NumLayers',a.NumLayers);
            obj.InitialAssignment=a; obj.UEId=double(ueId);
            obj.TBSBits=allocation.NominalTBSBits; obj.InitialTargetCodeRate=a.TargetCodeRate;
            obj.BaseGraph=plan.BaseGraph; obj.CombineSignature=string(plan.CombineSignature);
        end

        function allocation=allocation(obj,installed,a,ueId)
            sixgr.phy.pdcch.validateConnectedAssignment(installed,a);
            original=obj.InitialAssignment;
            assert(a.Direction=="DL" && a.ContextDigest==original.ContextDigest && ...
                double(ueId)==obj.UEId && a.RNTI==original.RNTI && ...
                a.HARQProcess==original.HARQProcess && a.NDI==original.NDI && ...
                a.ControlAbsoluteSlot>original.ControlAbsoluteSlot && ...
                a.DataAbsoluteSlot>original.DataAbsoluteSlot, ...
                'sixgr:pdsch:ReceivedDLHARQIdentityMismatch', ...
                'Retained coding belongs to the same UE/context/process/NDI and an earlier received assignment.');
            if a.RequiresHARQHistory
                allocation=sixgr.phy.pdcch.connectedDataAllocation(installed,a,obj.InitialTargetCodeRate);
            else
                allocation=sixgr.phy.pdcch.connectedDataAllocation(installed,a);
                assert(allocation.NominalTBSBits==obj.TBSBits, ...
                    'sixgr:pdsch:ReceivedDLHARQTBSChanged', ...
                    'This UE rejects a defined-MCS retransmission that changes the retained TB size.');
            end
        end

        function p=profile(obj,table,index)
            assert(isscalar(table) && string(table)==obj.InitialAssignment.MCSTable, ...
                'sixgr:pdsch:ReceivedDLHARQIdentityMismatch','Retained coding MCS table mismatch.');
            p=sixgr.phy.pdcch.resolveConnectedMCS(struct('mcsTable',table),double(index));
            % The received row still determines modulation. Original coding
            % rate determines LDPC segmentation, including modulation-only rows.
            p.NominalTargetCodeRate=p.TargetCodeRate;
            p.TargetCodeRate=obj.InitialTargetCodeRate;
        end

        function p=validateAssignmentData(obj,data)
            a=obj.InitialAssignment;
            assert(string(data.Profile)=="connected_strict" && ...
                string(data.Source)=="decoded_dci+ue_context" && ...
                string(data.ControlAuthority)=="receiver_crc_valid_decode" && data.RNTIType=="C-RNTI" && ...
                data.UEId==obj.UEId && data.RNTI==a.RNTI && ...
                data.HARQProcessId==a.HARQProcess && data.NDIPerCodeword==a.NDI && ...
                data.ConfigurationEpoch==a.ConfigurationEpoch && ...
                data.ReceivedContextDigest==a.ContextDigest && ...
                data.PDCCHAbsoluteSlot>a.ControlAbsoluteSlot && data.PDSCHAbsoluteSlot>a.DataAbsoluteSlot && ...
                data.NumCodewords==1, 'sixgr:pdsch:ReceivedDLHARQIdentityMismatch', ...
                'Immutable receiver history cannot authorize a different process, NDI, context or transmitter assignment.');
            p=obj.profile(data.MCSTablePerCodeword,data.MCSIndexPerCodeword);
            assert(isequaln(data.NominalReceivedMCSTargetCodeRate,p.NominalTargetCodeRate) && ...
                data.CodingRateSource=="retained_initial_received_assignment", ...
                'sixgr:pdsch:ReceivedDLHARQRateDomainMismatch', ...
                'Current table-row rate and retained initial coding rate must remain separately labeled.');
        end
    end
end
