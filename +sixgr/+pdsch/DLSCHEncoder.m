function encode = DLSCHEncoder(arg1, arg2)
%DLSCHENCODER Execute explicit DL-SCH coding from an immutable plan.
%   encode = DLSCHEncoder(tbBits, codingPlan) executes TB CRC attachment,
%   code-block segmentation/CRC, LDPC encoding, and rate matching using an
%   immutable sixgr.pdsch.DLSCHCodingPlan. Cell inputs execute two
%   independently planned codewords.

if nargin < 2
    error("sixgr:pdsch:DLSCHEncoder:NotEnoughInputs", ...
        "Transport bits and an immutable DLSCHCodingPlan are required.");
end

if ~localIsPlanCollection(arg2)
    error("sixgr:pdsch:DLSCHEncoder:MissingCodingPlan", ...
        "DL-SCH encoding requires an immutable DLSCHCodingPlan (or cell of plans); metadata-only tx/txInfo inference is forbidden.");
end
encode = localEncodeExplicit(arg1, arg2);
end

function encode = localEncodeExplicit(bits, plans)
[bitCells, planCells] = localNormalizeCodewords(bits, plans);
codewords = cell(1, numel(planCells));
for cw = 1:numel(planCells)
    codewords{cw} = localEncodeCodeword(bitCells{cw}, planCells{cw});
end
if isscalar(codewords)
    encode = codewords{1};
    return;
end
encode = struct( ...
    "ContractVersion", "ExplicitDLSCHEncode/v1", ...
    "NumCodewords", uint8(numel(codewords)), ...
    "Codewords", {codewords}, ...
    "CodingPlanIDs", string(cellfun(@(x) x.CodingPlanID, ...
        codewords, "UniformOutput", false)), ...
    "TransportBlocks", {cellfun(@(x) x.TransportBlock, ...
        codewords, "UniformOutput", false)}, ...
    "RateMatchedBits", {cellfun(@(x) x.RateMatchedBits, ...
        codewords, "UniformOutput", false)}, ...
    "Source", "explicit_dlsch_primitives_truth");
end

function out = localEncodeCodeword(bits, plan)
bits = localValidateTransportBlock(bits, plan);
layout = plan.toCodingLayout();

tbCRCBlock = sixgr.phy.tb.attachCRC(bits, plan.TBCRCType);
if numel(tbCRCBlock) ~= double(plan.TransportBlockLengthWithCRC)
    error("sixgr:pdsch:DLSCHEncoder:PlanMismatch", ...
        "TB CRC output length %d does not match plan B=%d.", ...
        numel(tbCRCBlock), double(plan.TransportBlockLengthWithCRC));
end
tbCRCBits = tbCRCBlock((end - double(plan.TBCRCLength) + 1):end);

[codeBlocks, segmentationInfo] = sixgr.phy.tb.segmentLDPC( ...
    tbCRCBlock, double(plan.BaseGraph));
localValidateSegmentation(codeBlocks, segmentationInfo, plan);
fillerMask = codeBlocks < 0;

[encodedCodeBlocks, ldpcEncodeInfo] = sixgr.phy.phycode.ldpcEncode( ...
    codeBlocks, double(plan.BaseGraph));
if ~isequal(size(encodedCodeBlocks), ...
        [double(plan.MotherCodeLength), double(plan.NumCodeBlocks)])
    error("sixgr:pdsch:DLSCHEncoder:PlanMismatch", ...
        "LDPC mother-code shape %s does not match plan [%d %d].", ...
        mat2str(size(encodedCodeBlocks)), double(plan.MotherCodeLength), ...
        double(plan.NumCodeBlocks));
end

if isempty(plan.Nref)
    [rateMatchedBits, rateMatchInfo] = sixgr.phy.phycode.rateMatchLDPC( ...
        encodedCodeBlocks, double(plan.RateMatchedBitCount), ...
        double(plan.RV), plan.Modulation, double(plan.NumLayers));
else
    [rateMatchedBits, rateMatchInfo] = sixgr.phy.phycode.rateMatchLDPC( ...
        encodedCodeBlocks, double(plan.RateMatchedBitCount), ...
        double(plan.RV), plan.Modulation, double(plan.NumLayers), ...
        double(plan.Nref));
end
if numel(rateMatchedBits) ~= double(plan.RateMatchedBitCount) || ...
        any(double(rateMatchedBits(:)) < 0)
    error("sixgr:pdsch:DLSCHEncoder:RateMatchFailure", ...
        "Rate matching did not produce exactly G non-filler bits.");
end
rateMatchInfo.PositionMap = layout.RateMatchPositionMap;
rateMatchInfo.CircularBufferPositionMap = layout.CircularBufferPositionMap;
rateMatchInfo.EPerCodeBlock = double(layout.E_r);
rateMatchInfo.CodingPlanID = plan.PlanID;
rateMatchInfo.PositionMapSource = ...
    "filler_aware_immutable_dlsch_coding_plan";

out = struct( ...
    "ContractVersion", "ExplicitDLSCHEncodeCodeword/v1", ...
    "CodewordIndex", plan.CodewordIndex, ...
    "CodingPlan", plan.toStruct(), ...
    "CodingPlanID", plan.PlanID, ...
    "CodingLayout", layout, ...
    "TransportBlock", int8(bits(:)), ...
    "TBCRCType", plan.TBCRCType, ...
    "TBCRCBlock", int8(tbCRCBlock(:)), ...
    "TBCRCBits", int8(tbCRCBits(:)), ...
    "BaseGraph", plan.BaseGraph, ...
    "CodeBlocks", int8(codeBlocks), ...
    "SegmentationInfo", segmentationInfo, ...
    "CodeBlockCRCType", plan.CBCRCType, ...
    "FillerMask", logical(fillerMask), ...
    "FillerPositionsZeroBased", {plan.FillerPositionsZeroBased}, ...
    "EncodedCodeBlocks", int8(encodedCodeBlocks), ...
    "LDPCEncodeInfo", ldpcEncodeInfo, ...
    "RateMatchedBits", int8(rateMatchedBits(:)), ...
    "RateMatchInfo", rateMatchInfo, ...
    "Source", "explicit_dlsch_primitives_truth");
end

function bits = localValidateTransportBlock(bits, plan)
if ~(isnumeric(bits) || islogical(bits)) || ~isvector(bits)
    error("sixgr:pdsch:DLSCHEncoder:BadTransportBlock", ...
        "Transport block must be a numeric or logical bit vector.");
end
bits = double(bits(:));
if numel(bits) ~= double(plan.TransportBlockSize)
    error("sixgr:pdsch:DLSCHEncoder:TransportBlockSizeMismatch", ...
        "Transport block has %d bits; coding plan requires A=%d.", ...
        numel(bits), double(plan.TransportBlockSize));
end
if any(~isfinite(bits) | (bits ~= 0 & bits ~= 1))
    error("sixgr:pdsch:DLSCHEncoder:BadTransportBlock", ...
        "Transport block values must be binary 0 or 1.");
end
bits = int8(bits);
end

function localValidateSegmentation(codeBlocks, info, plan)
if size(codeBlocks, 1) ~= double(plan.CodeBlockLength) || ...
        size(codeBlocks, 2) ~= double(plan.NumCodeBlocks) || ...
        double(info.FillerCount) ~= double(plan.FillerCount)
    error("sixgr:pdsch:DLSCHEncoder:PlanMismatch", ...
        ["Code-block segmentation shape/filler count does not match the " ...
        "immutable coding plan."]);
end
for c = 1:numel(plan.FillerPositionsZeroBased)
    actual = uint32(double(find(codeBlocks(:, c) < 0)) - 1);
    if ~isequal(actual(:), plan.FillerPositionsZeroBased{c}(:))
        error("sixgr:pdsch:DLSCHEncoder:PlanMismatch", ...
            "Filler positions for code block %d do not match the plan.", c - 1);
    end
end
end

function tf = localIsPlanCollection(value)
tf = isa(value, "sixgr.pdsch.DLSCHCodingPlan");
if iscell(value)
    tf = ~isempty(value) && all(cellfun( ...
        @(x) isa(x, "sixgr.pdsch.DLSCHCodingPlan"), value(:)));
end
end

function [bits, plans] = localNormalizeCodewords(bits, plans)
if ~iscell(plans)
    plans = {plans};
else
    plans = reshape(plans, 1, []);
end
if ~iscell(bits)
    if numel(plans) ~= 1
        error("sixgr:pdsch:DLSCHEncoder:CodewordCountMismatch", ...
            "Two coding plans require a cell containing two transport blocks.");
    end
    bits = {bits};
else
    bits = reshape(bits, 1, []);
end
if numel(bits) ~= numel(plans) || ~ismember(numel(plans), [1 2])
    error("sixgr:pdsch:DLSCHEncoder:CodewordCountMismatch", ...
        "DL-SCH coding requires one or two equally counted blocks and plans.");
end
indices = cellfun(@(x) double(x.CodewordIndex), plans);
if ~isequal(indices, 0:(numel(plans) - 1))
    error("sixgr:pdsch:DLSCHEncoder:CodewordIndexMismatch", ...
        "Coding plans must be ordered with zero-based indices 0..N-1.");
end
end
