function summary = runPDSCHPhaseValidation(varargin)
%RUNPDSCHPHASEVALIDATION Execute and publish the Prompt-02 PDSCH phase.
%
% SUMMARY = sixgr.pdsch.runPDSCHPhaseValidation( ...
%     "VectorRoot", VECTORROOT, "OutputDir", OUTPUTDIR, ...
%     "SeedList", [11 23 47 89], "ConfidenceLevel", 0.95, ...
%     "Strict", true)
%
% The runner verifies the immutable vector pack before executing MATLAB
% evidence, calls the production evidence builder and coverage executor,
% and publishes one transactional result directory. Expected-vector files
% are comparison inputs only and are never copied to the output.

defaultVectorRoot = fullfile(pwd, "tests", "vectors", "pdsch");
defaultOutputDir = fullfile(pwd, "artifacts", "pdsch_dlsch_phase");
ip = inputParser;
ip.FunctionName = "sixgr.pdsch.runPDSCHPhaseValidation";
ip.addParameter("VectorRoot", defaultVectorRoot, ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));
ip.addParameter("OutputDir", defaultOutputDir, ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));
ip.addParameter("SeedList", [11 23 47 89], ...
    @(x) isnumeric(x) && isvector(x) && ~isempty(x));
ip.addParameter("ConfidenceLevel", 0.95, ...
    @(x) isnumeric(x) && isscalar(x) ...
    && isfinite(x) && x > 0 && x < 1);
ip.addParameter("Strict", true, ...
    @(x) islogical(x) && isscalar(x));
ip.parse(varargin{:});
opt = ip.Results;

vectorRoot = char(string(opt.VectorRoot));
outputDir = char(string(opt.OutputDir));
seeds = double(opt.SeedList(:).');
if strlength(strtrim(string(vectorRoot))) == 0 || ~isfolder(vectorRoot)
    error("sixgr:pdsch:PDSCHPhaseValidation:VectorRootMissing", ...
        "VectorRoot must identify the frozen PDSCH vector pack.");
end
if strlength(strtrim(string(outputDir))) == 0
    error("sixgr:pdsch:PDSCHPhaseValidation:OutputDirectoryMissing", ...
        "OutputDir must be a nonempty path.");
end
if any(~isfinite(seeds) | seeds ~= fix(seeds))
    error("sixgr:pdsch:PDSCHPhaseValidation:InvalidSeedList", ...
        "SeedList must contain finite integers.");
end

phaseStarted = tic;
localRequireFreshOutput(outputDir);
vectorStarted = tic;
[vectorStatus, vectorOutput, vectorCommand, vectorCount] = ...
    localVerifyVectorPack(vectorRoot);
vectorDuration = toc(vectorStarted);
vectorExecution = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
    executionRow( ...
    "vector_pack_verification", ...
    "verify_pdsch_vector_pack.py", ...
    "python_preflight", ...
    repmat(vectorStatus == 0, vectorCount, 1), ...
    vectorDuration, ...
    "files=" + string(vectorCount) ...
    + " exit=" + string(vectorStatus));
if vectorStatus ~= 0
    error("sixgr:pdsch:PDSCHPhaseValidation:VectorPackVerificationFailed", ...
        "Frozen PDSCH vector verification failed:\n%s", vectorOutput);
end

if exist("setup6GRSimToolkit", "file") ~= 2
    error("sixgr:pdsch:PDSCHPhaseValidation:ToolkitSetupMissing", ...
        "setup6GRSimToolkit is required for phase execution.");
end
setup6GRSimToolkit("Verbose", false);
standardsBaseline = struct( ...
    "TS38211", "3GPP TS 38.211 V18.8.0", ...
    "TS38212", "3GPP TS 38.212 V18.8.0", ...
    "TS38213", "3GPP TS 38.213 V18.8.0", ...
    "TS38214", "3GPP TS 38.214 V18.8.0", ...
    "TS38331", "3GPP TS 38.331 V18.8.0", ...
    "MATLABRelease", string(version("-release")));
fprintf([ ...
    "PDSCH standards baseline: %s | %s | %s | %s | %s | MATLAB %s\n"], ...
    standardsBaseline.TS38211, standardsBaseline.TS38212, ...
    standardsBaseline.TS38213, standardsBaseline.TS38214, ...
    standardsBaseline.TS38331, standardsBaseline.MATLABRelease);

builderStarted = tic;
builder = sixgr.pdsch.PDSCHPhaseEvidenceBuilder.build(vectorRoot);
builderDuration = toc(builderStarted);
localValidateBuilder(builder);
builderExecution = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
    executionRow( ...
    "phase_evidence_builder", ...
    "sixgr.pdsch.PDSCHPhaseEvidenceBuilder.build", ...
    "production_evidence_builder", ...
    localStructStatuses(builder), builderDuration, ...
    "tables=" + string(numel(fieldnames(builder))));
localRequirePassingExecution(builderExecution, "evidence builder");

coverageStarted = tic;
coverage = sixgr.pdsch.PDSCHStudyCoverageExecutor.run( ...
    "VectorRoot", vectorRoot, ...
    "SeedList", seeds, ...
    "ConfidenceLevel", double(opt.ConfidenceLevel), ...
    "Strict", logical(opt.Strict));
coverageDuration = toc(coverageStarted);
localValidateCoverage(coverage);
coverageExecution = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
    executionRow( ...
    "coverage_executor", ...
    "sixgr.pdsch.PDSCHStudyCoverageExecutor.run", ...
    "production_coverage_executor", ...
    localStructStatuses(coverage), coverageDuration, ...
    "declared=" + string(height(coverage.DeclaredCoverageResults)) ...
    + " pairwise=" + string(height(coverage.PairwiseCases)) ...
    + " no_noise=" + string(height(coverage.NoNoiseRoundTrip)) ...
    + " bler=" + string(height(coverage.BLERCurve)));
localRequirePassingExecution(coverageExecution, "coverage executor");

[focusedSummary, focusedExecution] = ...
    localRunFocusedSuites(vectorRoot);
requiredSuites = string(sixgr.pdsch. ...
    PDSCHPhaseFocusedTestExecutor.requiredSuiteNames());
directSuiteCount = nnz( ...
    requiredSuites ~= "testPDSCHArtifactGeneration");
if height(focusedSummary) ~= directSuiteCount ...
        || height(focusedExecution) ~= directSuiteCount
    error("sixgr:pdsch:PDSCHPhaseValidation:FocusedSuiteCountMismatch", ...
        "Expected %d direct nonrecursive PDSCH test executions.", ...
        directSuiteCount);
end

parentDir = fileparts(outputDir);
if isempty(parentDir)
    parentDir = pwd;
end
if ~isfolder(parentDir)
    [created, message] = mkdir(parentDir);
    if ~created
        error("sixgr:pdsch:PDSCHPhaseValidation:OutputParentCreateFailed", ...
            "Unable to create output parent directory: %s", message);
    end
end
stageDir = fullfile(parentDir, ".pdsch-stage-" + ...
    string(java.util.UUID.randomUUID()));
if isfile(stageDir) || isfolder(stageDir)
    error("sixgr:pdsch:PDSCHPhaseValidation:StageCollision", ...
        "Unique transactional stage already exists: %s",stageDir);
end
cleanup = onCleanup(@() localRemoveStage(stageDir));

preExecution = [ ...
    vectorExecution; ...
    builderExecution; ...
    coverageExecution; ...
    focusedExecution];
assembly = sixgr.pdsch.PDSCHPhaseArtifactPublisher.prepare( ...
    builder, coverage, focusedSummary, preExecution, ...
    stageDir, vectorRoot);

testsDir = fileparts(fileparts(vectorRoot));
priorPath = path;
testPathCleanup = onCleanup(@() path(priorPath));
addpath(testsDir);
[artifactOK, artifactValidation] = ...
    testPDSCHArtifactGeneration(stageDir, vectorRoot);
if ~artifactOK
    error("sixgr:pdsch:PDSCHPhaseValidation:ArtifactTestFailed", ...
        "testPDSCHArtifactGeneration returned false.");
end
finalized = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
    recordValidation(assembly, artifactValidation);

[finalValidationOK, finalArtifactValidation] = ...
    testPDSCHArtifactGeneration(stageDir, vectorRoot);
if ~finalValidationOK
    error("sixgr:pdsch:PDSCHPhaseValidation:FinalArtifactTestFailed", ...
        "Final artifact revalidation returned false.");
end
clear testPathCleanup
path(priorPath);

inventory = sixgr.pdsch.PDSCHPhaseArtifactPublisher.inventory(stageDir);
sixgr.pdsch.PDSCHPhaseArtifactPublisher.validateInventory( ...
    inventory, 20, 11, "final phase artifact contract");
phaseExecution = finalized.PhaseExecutionSummary;
testSummary = finalized.TestSummary;
if height(testSummary) ~= numel(requiredSuites)
    error("sixgr:pdsch:PDSCHPhaseValidation:TestSummaryCountMismatch", ...
        "Expected %d direct suites plus one real artifact-stage suite.", ...
        directSuiteCount);
end
passed = logical(finalized.Passed) ...
    && logical(finalArtifactValidation.Passed) ...
    && all(phaseExecution.Status == "PASS") ...
    && all(testSummary.Status == "PASS") ...
    && all(inventory.Status == "PASS");
if ~passed
    error("sixgr:pdsch:PDSCHPhaseValidation:FinalEvidenceFailed", ...
        "Final phase evidence contains a non-passing observed result.");
end
localPublishStage(stageDir, outputDir);
clear cleanup
exportSummary = finalized.ExporterSummary;
exportSummary.OutputDir = string(outputDir);
phaseDuration = toc(phaseStarted);

summary = struct( ...
    "ContractVersion", "PDSCHPhaseValidation/v2", ...
    "Passed", passed, ...
    "VectorRoot", string(vectorRoot), ...
    "OutputDir", string(outputDir), ...
    "SeedList", seeds, ...
    "ConfidenceLevel", double(opt.ConfidenceLevel), ...
    "Strict", logical(opt.Strict), ...
    "StandardsBaseline", standardsBaseline, ...
    "VectorPackVerificationCommand", string(vectorCommand), ...
    "VectorPackVerificationOutput", string(strtrim(vectorOutput)), ...
    "VectorPackFileCount", double(vectorCount), ...
    "BuilderPrimaryTableCount", double(numel(fieldnames(builder))), ...
    "DeclaredCoverageExecutionCount", ...
        double(height(coverage.DeclaredCoverageResults)), ...
    "PairwiseExecutionCount", double(height(coverage.PairwiseCases)), ...
    "NoNoiseExecutionCount", double(height(coverage.NoNoiseRoundTrip)), ...
    "BLEROperatingPointCount", double(height(coverage.BLERCurve)), ...
    "FocusedTestFunctionCount", double(height(focusedExecution)), ...
    "FocusedTestExecution", focusedExecution, ...
    "TestSummary", testSummary, ...
    "PhaseExecutionSummary", phaseExecution, ...
    "ArtifactInventory", inventory, ...
    "CSVFiles", inventory.FileName(inventory.Kind == "CSV"), ...
    "PNGFiles", inventory.FileName(inventory.Kind == "PNG"), ...
    "CSVCountBeforePythonVerifier", double(nnz( ...
        assembly.ArtifactInventory.Kind == "CSV")), ...
    "CSVCount", double(nnz(inventory.Kind == "CSV")), ...
    "PNGCount", double(nnz(inventory.Kind == "PNG")), ...
    "AdditionalCSVFiles", finalized.AdditionalCSVFiles, ...
    "ArtifactValidation", artifactValidation, ...
    "FinalArtifactValidation", finalArtifactValidation, ...
    "ArtifactVerifierExitCode", ...
        double(finalArtifactValidation.VerifierExitCode), ...
    "ArtifactVerifierOutput", ...
        string(finalArtifactValidation.VerifierOutput), ...
    "PhaseDurationSeconds", double(phaseDuration), ...
    "ExporterSummary", exportSummary);
end

function localRequireFreshOutput(outputDir)
if isfile(outputDir)
    error("sixgr:pdsch:PDSCHPhaseValidation:OutputPathIsFile", ...
        "OutputDir resolves to an existing file: %s", outputDir);
end
if ~isfolder(outputDir)
    return;
end
entries = dir(outputDir);
names = string({entries.name});
entries = entries(~ismember(names, [".",".."]));
if ~isempty(entries)
    error("sixgr:pdsch:PDSCHPhaseValidation:OutputDirectoryNotEmpty", ...
        "Refusing to mix phase evidence with existing OutputDir contents.");
end
end

function [status, output, command, vectorCount] = ...
        localVerifyVectorPack(vectorRoot)
script = fullfile(vectorRoot, "verify_pdsch_vector_pack.py");
manifest = fullfile(vectorRoot, "independent_vector_manifest.json");
if ~isfile(script) || ~isfile(manifest)
    error("sixgr:pdsch:PDSCHPhaseValidation:VectorVerifierMissing", ...
        "The frozen vector verifier and manifest are both required.");
end
if contains(string(script), '"')
    error("sixgr:pdsch:PDSCHPhaseValidation:UnsafeVerifierPath", ...
        "Vector verifier path contains an unsupported quote character.");
end
command = sprintf('python "%s"', script);
[status, output] = system(command);
manifestValue = jsondecode(fileread(manifest));
if ~isfield(manifestValue, "files")
    error("sixgr:pdsch:PDSCHPhaseValidation:VectorManifestInvalid", ...
        "Independent-vector manifest does not contain a files array.");
end
vectorCount = numel(manifestValue.files);
end

function localValidateBuilder(builder)
expected = [ ...
    "pdsch_assignment_resolution"; ...
    "pdsch_resource_ownership"; ...
    "pdsch_re_mapping"; ...
    "pdsch_dmrs_matrix"; ...
    "pdsch_ptrs_matrix"; ...
    "pdsch_coding_chain"; ...
    "pdsch_independent_vector_results"; ...
    "pdsch_layer_codeword_map"; ...
    "pdsch_precoding_application"; ...
    "pdsch_harq_trials"; ...
    "pdsch_negative_tests"];
if ~isstruct(builder) || ~isscalar(builder) ...
        || ~isequal(sort(string(fieldnames(builder))), sort(expected))
    error("sixgr:pdsch:PDSCHPhaseValidation:BuilderContractMismatch", ...
        "PDSCHPhaseEvidenceBuilder returned an unexpected field contract.");
end
for name = expected.'
    localRequirePassingTable(builder.(name), ...
        "builder." + name);
end
end

function localValidateCoverage(coverage)
required = [ ...
    "Passed","DeclaredCoverageResults","PairwiseCases", ...
    "NoNoiseRoundTrip","ReceiverMetrics","BLERCurve", ...
    "NegativeTests","TestSummary","FadingTruthAnchors"];
if ~isstruct(coverage) || ~isscalar(coverage) ...
        || any(~isfield(coverage, required))
    error("sixgr:pdsch:PDSCHPhaseValidation:CoverageContractMismatch", ...
        "PDSCHCoverageExecutor returned an incomplete contract.");
end
if ~logical(coverage.Passed)
    error("sixgr:pdsch:PDSCHPhaseValidation:CoverageFailed", ...
        "PDSCHCoverageExecutor returned Passed=false.");
end
tableNames = required(2:end);
for name = tableNames
    localRequirePassingTable(coverage.(name), ...
        "coverage." + name);
end
end

function [summary, execution] = localRunFocusedSuites(vectorRoot)
names = localRequiredSuiteNames();
[summary, execution] = sixgr.pdsch. ...
    PDSCHPhaseFocusedTestExecutor.run(vectorRoot, names);
end

function names = localRequiredSuiteNames()
names = sixgr.pdsch.PDSCHPhaseFocusedTestExecutor. ...
    requiredSuiteNames();
requiredRegressions = [ ...
    "testPDSCHPhaseRunnerHonesty"; ...
    "testPDSCHFadingHighRank"; ...
    "testPDSCHBLERStopPolicy"];
if any(~ismember(requiredRegressions, names))
    error("sixgr:pdsch:PDSCHPhaseValidation:RequiredSuiteMissing", ...
        "The selected PDSCH suite omits a required honesty/R2026a regression.");
end
end

function localRequirePassingTable(value, label)
if ~istable(value) || height(value) < 1
    error("sixgr:pdsch:PDSCHPhaseValidation:EmptyEvidenceTable", ...
        "%s must contain observed production rows.", label);
end
if ~ismember("Status", string(value.Properties.VariableNames))
    error("sixgr:pdsch:PDSCHPhaseValidation:StatusColumnMissing", ...
        "%s does not contain a Status column.", label);
end
status = upper(strtrim(string(value.Status)));
if any(status ~= "PASS")
    error("sixgr:pdsch:PDSCHPhaseValidation:NonPassEvidence", ...
        "%s contains one or more non-passing rows.", label);
end
end

function statuses = localStructStatuses(value)
statuses = strings(0, 1);
names = string(fieldnames(value));
for name = names.'
    item = value.(name);
    if istable(item) && ~isempty(item) ...
            && ismember("Status", string(item.Properties.VariableNames))
        statuses = [statuses; ...
            upper(strtrim(string(item.Status)))]; %#ok<AGROW>
    end
end
if isempty(statuses)
    error("sixgr:pdsch:PDSCHPhaseValidation:NoObservedStatuses", ...
        "Production stage did not return any observed status rows.");
end
end

function localRequirePassingExecution(value, label)
if ~istable(value) || height(value) ~= 1 ...
        || ~ismember("Status", string(value.Properties.VariableNames)) ...
        || string(value.Status) ~= "PASS"
    error("sixgr:pdsch:PDSCHPhaseValidation:StageFailed", ...
        "%s did not produce a passing observed execution row.", label);
end
end

function localPublishStage(stageDir, outputDir)
if isfolder(outputDir)
    entries = dir(outputDir);
    names = string({entries.name});
    entries = entries(~ismember(names, [".",".."]));
    if ~isempty(entries)
        error("sixgr:pdsch:PDSCHPhaseValidation:OutputDirectoryChanged", ...
            "OutputDir gained contents while phase evidence was executing.");
    end
    [removed, message] = rmdir(outputDir);
    if ~removed
        error("sixgr:pdsch:PDSCHPhaseValidation:EmptyOutputRemoveFailed", ...
            "Unable to replace the empty OutputDir: %s", message);
    end
end
[moved, message] = movefile(stageDir, outputDir);
if ~moved
    error("sixgr:pdsch:PDSCHPhaseValidation:ArtifactPublishFailed", ...
        "Unable to publish the transactional phase directory: %s", message);
end
end

function localRemoveStage(path)
if isfolder(path)
    rmdir(path, "s");
end
end

function value = localTernary(condition, whenTrue, whenFalse)
if logical(condition)
    value = whenTrue;
else
    value = whenFalse;
end
end
