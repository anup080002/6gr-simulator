classdef CORESETQCLReference
    % TS 38.214 5.1.5: absent-TCI PDSCH inherits the scheduling CORESET QCL.
    % This is an installed association, not measurement or parameter reuse.
    methods (Static)
        function validatePolicy(p)
            fields={'configuration_epoch','serving_cell_index','component_carrier_index', ...
                'bwp_id','coreset_id','activation_absolute_slot0','source_reference_signal', ...
                'source_reference_signal_id','qcl_types','initialization_source'};
            assert(isstruct(p) && isscalar(p) && all(isfield(p,fields)) && ...
                isempty(setdiff(fieldnames(p),fields)), ...
                'sixgr:qcl:MissingCORESETAssociation','An explicit complete CORESET QCL association is required.');
            for name=fields([1:6 8])
                validateattributes(p.(name{1}),{'numeric'},{'scalar','integer','finite','nonnegative'});
            end
            types=string(p.qcl_types(:).');
            assert(~isempty(types) && all(ismember(types,["A","B","C","D"])) && ...
                numel(unique(types))==numel(types) && ...
                any(string(p.source_reference_signal)==["SSB","NZP-CSI-RS"]) && ...
                string(p.initialization_source)=="lls_preconfigured_higher_layer_context", ...
                'sixgr:qcl:InvalidCORESETAssociation','Invalid reference identity, QCL types or initialization source.');
            % Type-D needs an actually applied receive spatial filter and
            % capability-dependent short-offset/monitored-CORESET history.
            assert(~any(types=="D"),'sixgr:qcl:CORESETSpatialReuseUnqualified', ...
                'Type-D default QCL requires received spatial-filter and scheduling-offset integration.');
            maximum=191;
            if string(p.source_reference_signal)=="SSB", maximum=63; end
            assert(p.source_reference_signal_id<=maximum,'sixgr:qcl:InvalidCORESETAssociation', ...
                'Reference identity lies outside its NR resource namespace.');
        end

        function p=policyForContext(cfg,context)
            p=sixgr.util.structGet(cfg,'phy.pdcch.operatorControl.coreset_qcl_association',struct());
            sixgr.pdsch.CORESETQCLReference.validatePolicy(p);
            d=context.Data;
            assert(p.configuration_epoch==d.ConfigurationEpoch && ...
                p.serving_cell_index==d.ControlServingCell && ...
                p.component_carrier_index==d.ControlCarrier && ...
                p.bwp_id==d.ControlBWP && p.coreset_id==d.CORESETID && ...
                d.ControlServingCell==d.ScheduledServingCell && d.ControlCarrier==d.ScheduledCarrier, ...
                'sixgr:qcl:CORESETAssociationIdentityMismatch','CORESET association must match the installed same-cell control context.');
        end

        function reference=fromInstalled(cfg,context,controlSlot)
            p=sixgr.pdsch.CORESETQCLReference.policyForContext(cfg,context);
            validateattributes(controlSlot,{'numeric'},{'scalar','integer','finite','nonnegative'});
            assert(controlSlot>=p.activation_absolute_slot0,'sixgr:qcl:InactiveCORESETAssociation', ...
                'The received PDCCH cannot use a future CORESET association.');
            reference=struct('Policy',p,'ControlAbsoluteSlot',double(controlSlot), ...
                'SourceReferenceSignal',string(p.source_reference_signal), ...
                'SourceReferenceSignalId',string(p.source_reference_signal_id), ...
                'QCLTypes',strjoin(string(p.qcl_types(:).'),"|"), ...
                'Assumptions',"scheduling_CORESET_QCL_association_TS_38_214_5_1_5", ...
                'BindingKind',"installed_coreset_qcl_without_dci_tci", ...
                'TCIActivationApplicable',false, ...
                'ReceiverParameterReuseStatus',"association_only_no_measured_timing_or_spatial_reuse");
        end

        function reference=validate(reference,data)
            required={'Policy','ControlAbsoluteSlot','SourceReferenceSignal','SourceReferenceSignalId', ...
                'QCLTypes','Assumptions','BindingKind','TCIActivationApplicable','ReceiverParameterReuseStatus'};
            assert(isstruct(reference) && isscalar(reference) && all(isfield(reference,required)), ...
                'sixgr:qcl:MissingCORESETAssociation','Default QCL requires the received CORESET association.');
            p=reference.Policy; sixgr.pdsch.CORESETQCLReference.validatePolicy(p);
            assert(string(data.Profile)=="connected_strict" && ...
                string(data.ControlAuthority)=="receiver_crc_valid_decode" && ...
                isfield(data,'ReceivedTCIPresent') && isequal(data.ReceivedTCIPresent,false) && ...
                isnan(data.TCIStateId) && isnan(data.TransmissionConfigurationIndication) && ...
                p.configuration_epoch==data.ConfigurationEpoch && ...
                p.serving_cell_index==data.ServingCellId && data.ServingCellId==data.SchedulingCellId && ...
                p.component_carrier_index==data.CCId && p.bwp_id==data.BWPId && ...
                string(p.coreset_id)==string(data.CORESETId) && ...
                reference.ControlAbsoluteSlot==data.PDCCHAbsoluteSlot && ...
                reference.ControlAbsoluteSlot>=p.activation_absolute_slot0 && ...
                reference.SourceReferenceSignal==string(p.source_reference_signal) && ...
                reference.SourceReferenceSignalId==string(p.source_reference_signal_id) && ...
                reference.QCLTypes==strjoin(string(p.qcl_types(:).'),"|") && ...
                reference.Assumptions=="scheduling_CORESET_QCL_association_TS_38_214_5_1_5" && ...
                reference.BindingKind=="installed_coreset_qcl_without_dci_tci" && ...
                isequal(reference.TCIActivationApplicable,false) && ...
                reference.ReceiverParameterReuseStatus=="association_only_no_measured_timing_or_spatial_reuse", ...
                'sixgr:qcl:CORESETAssociationIdentityMismatch', ...
                'Default QCL association must belong to this received assignment; no fabricated TCI or measured reuse.');
        end
    end
end
