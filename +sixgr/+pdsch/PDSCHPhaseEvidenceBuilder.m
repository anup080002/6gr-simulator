classdef PDSCHPhaseEvidenceBuilder
    %PDSCHPHASEEVIDENCEBUILDER Execute frozen vectors into artifact tables.
    %
    % The builder is deliberately fail closed.  Expected-vector files are
    % used only to decide whether an observed production result passed its
    % frozen contract.  Returned rows are populated from the observed
    % objects, indices, sequences, decoded bits, traces, and typed errors.

    methods (Static)
        function tables = build(vectorRoot)
            vectorRoot = char(string(vectorRoot));
            if ~isfolder(vectorRoot)
                error("sixgr:pdsch:PhaseEvidenceVectorRootMissing", ...
                    "PDSCH vector root does not exist: %s", vectorRoot);
            end
            contractPath = fullfile(vectorRoot, ...
                "desired_pdsch_csv_contract.csv");
            if ~isfile(contractPath)
                error("sixgr:pdsch:PhaseEvidenceContractMissing", ...
                    "The exact PDSCH CSV contract is required.");
            end

            negativeRows = cell(0, 1);
            evidence = cell(0, 1);

            [assignmentRows, observedNegatives] = ...
                localBuildAssignments(vectorRoot);
            negativeRows = [negativeRows; observedNegatives]; %#ok<AGROW>

            [ownershipRows, mappingRows, reservationCodingRows, ...
                observedNegatives, observedEvidence] = ...
                localBuildResources(vectorRoot);
            negativeRows = [negativeRows; observedNegatives]; %#ok<AGROW>
            evidence = [evidence; observedEvidence]; %#ok<AGROW>

            [dmrsRows, observedNegatives, observedEvidence] = ...
                localBuildDMRS(vectorRoot);
            negativeRows = [negativeRows; observedNegatives]; %#ok<AGROW>
            evidence = [evidence; observedEvidence]; %#ok<AGROW>

            [ptrsRows, observedNegatives, observedEvidence] = ...
                localBuildPTRS(vectorRoot);
            negativeRows = [negativeRows; observedNegatives]; %#ok<AGROW>
            evidence = [evidence; observedEvidence]; %#ok<AGROW>

            [codingRows, observedNegatives, observedEvidence] = ...
                localBuildCoding(vectorRoot);
            codingRows = [codingRows; reservationCodingRows]; %#ok<AGROW>
            negativeRows = [negativeRows; observedNegatives]; %#ok<AGROW>
            evidence = [evidence; observedEvidence]; %#ok<AGROW>

            [layerRows, observedNegatives, observedEvidence] = ...
                localBuildLayers(vectorRoot);
            negativeRows = [negativeRows; observedNegatives]; %#ok<AGROW>
            evidence = [evidence; observedEvidence]; %#ok<AGROW>

            [precodingRows, observedNegatives, observedEvidence] = ...
                localBuildPrecoding(vectorRoot);
            negativeRows = [negativeRows; observedNegatives]; %#ok<AGROW>
            evidence = [evidence; observedEvidence]; %#ok<AGROW>

            [harqRows, observedNegatives, observedEvidence] = ...
                localBuildHARQ(vectorRoot);
            negativeRows = [negativeRows; observedNegatives]; %#ok<AGROW>
            evidence = [evidence; observedEvidence]; %#ok<AGROW>

            evidence = [evidence; ...
                localBuildScramblingEvidence(vectorRoot)]; %#ok<AGROW>
            [modEvidence, modNegatives] = ...
                localBuildModulationEvidence(vectorRoot);
            evidence = [evidence; modEvidence]; %#ok<AGROW>
            negativeRows = [negativeRows; modNegatives]; %#ok<AGROW>

            evidence = [evidence; localBuildReceiverEvidence(vectorRoot)]; %#ok<AGROW>
            independentRows = localEvidenceRows(evidence);

            tables = struct();
            tables.pdsch_assignment_resolution = localContractTable( ...
                vectorRoot, "pdsch_assignment_resolution.csv", assignmentRows);
            tables.pdsch_resource_ownership = localContractTable( ...
                vectorRoot, "pdsch_resource_ownership.csv", ownershipRows);
            tables.pdsch_re_mapping = localContractTable( ...
                vectorRoot, "pdsch_re_mapping.csv", mappingRows);
            tables.pdsch_dmrs_matrix = localContractTable( ...
                vectorRoot, "pdsch_dmrs_matrix.csv", dmrsRows);
            tables.pdsch_ptrs_matrix = localContractTable( ...
                vectorRoot, "pdsch_ptrs_matrix.csv", ptrsRows);
            tables.pdsch_coding_chain = localContractTable( ...
                vectorRoot, "pdsch_coding_chain.csv", codingRows);
            tables.pdsch_independent_vector_results = localContractTable( ...
                vectorRoot, "pdsch_independent_vector_results.csv", ...
                independentRows);
            tables.pdsch_layer_codeword_map = localContractTable( ...
                vectorRoot, "pdsch_layer_codeword_map.csv", layerRows);
            tables.pdsch_precoding_application = localContractTable( ...
                vectorRoot, "pdsch_precoding_application.csv", precodingRows);
            tables.pdsch_harq_trials = localContractTable( ...
                vectorRoot, "pdsch_harq_trials.csv", harqRows);
            tables.pdsch_negative_tests = localContractTable( ...
                vectorRoot, "pdsch_negative_tests.csv", negativeRows);
        end
    end
end

function [rows, negatives] = localBuildAssignments(root)
vectors = localReadStrings(fullfile(root, ...
    "pdsch_scheduling_assignment_test_vectors.csv"));
expected = localReadStrings(fullfile(root, ...
    "expected_pdsch_assignment_resolution.csv"));
rows = cell(height(vectors), 1);
negatives = cell(0, 1);
for i = 1:height(vectors)
    vector = vectors(i, :);
    frozen = expected(expected.CaseID == vector.CaseID, :);
    localRequire(height(frozen) == 1, ...
        "sixgr:pdsch:PhaseEvidenceMissingExpectedAssignment", ...
        "Missing frozen assignment result for %s.", vector.CaseID);
    [assignment, actualError] = localAssignmentFromVector(vector);
    expectedStatus = upper(frozen.ExpectedStatus);
    if expectedStatus == "PASS"
        localRequire(~isempty(assignment) && strlength(actualError) == 0, ...
            "sixgr:pdsch:PhaseEvidenceAssignmentMismatch", ...
            "%s expected an assignment but observed %s.", ...
            vector.CaseID, actualError);
        data = assignment.toStruct();
        localRequire(string(data.Source) == frozen.ExpectedAssignmentSource, ...
            "sixgr:pdsch:PhaseEvidenceAssignmentSourceMismatch", ...
            "%s source mismatch: %s versus %s.", vector.CaseID, ...
            data.Source, frozen.ExpectedAssignmentSource);
        row = localAssignmentRowFromData(vector.CaseID, data);
    else
        expectedError = "sixgr:pdsch:" + frozen.ExpectedError;
        localRequire(isempty(assignment) && actualError == expectedError, ...
            "sixgr:pdsch:PhaseEvidenceAssignmentErrorMismatch", ...
            "%s expected %s but observed %s.", ...
            vector.CaseID, expectedError, actualError);
        row = localRejectedAssignmentRow(vector, actualError);
        negatives{end + 1, 1} = localNegativeRow( ... %#ok<AGROW>
            vector.CaseID, "assignment_resolution", ...
            expectedError, actualError);
    end
    rows{i} = row;
end
end

function [assignment, observedError] = localAssignmentFromVector(row)
[decoded, ue, frame, harq] = localAssignmentInputs(row);
assignment = [];
observedError = "";
try
    switch lower(row.Profile)
        case {"connected_strict","ra_si_strict"}
            assignment = sixgr.pdsch.PDSCHAssignmentFactory.fromDecodedDCI( ...
                decoded, sixgr.pdsch.PDSCHUEContext(ue), frame, harq);
        case "sps_strict"
            sps = localSPSContext(row, decoded);
            assignment = sixgr.pdsch.PDSCHAssignmentFactory.fromSPSOccasion( ...
                sixgr.pdsch.PDSCHSPSContext(sps), ...
                sixgr.pdsch.PDSCHUEContext(ue), frame, harq);
        case "phy_calibration"
            request = localCalibrationRequest(decoded, ue);
            assignment = sixgr.pdsch.PDSCHAssignmentFactory.forCalibration( ...
                request, frame);
        otherwise
            error("sixgr:pdsch:UnsupportedExecutionProfile", ...
                "Unsupported execution profile '%s'.", row.Profile);
    end
catch ME
    observedError = string(ME.identifier);
end
end

