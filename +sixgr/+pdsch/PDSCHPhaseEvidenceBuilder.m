function values = localDecodeIntegers(text)
text = strtrim(string(text));
if ismissing(text) || strlength(text) == 0
    values = zeros(1, 0);
    return;
end
tokens = split(text, "|");
values = zeros(1, 0);
for i = 1:numel(tokens)
    token = strtrim(tokens(i));
    range = regexp(char(token), ...
        '^(-?\d+)-(-?\d+)$', "tokens", "once");
    if isempty(range)
        values(end + 1) = str2double(token); %#ok<AGROW>
    else
        first = str2double(range{1});
        last = str2double(range{2});
        if first <= last
            values = [values first:last]; %#ok<AGROW>
        else
            values = [values first:-1:last]; %#ok<AGROW>
        end
    end
end
localRequire(all(isfinite(values) & values == floor(values)), ...
    "sixgr:pdsch:PhaseEvidenceInvalidEncodedIntegers", ...
    "Invalid encoded integer vector '%s'.", text);
end

function values = localDecodeNumbers(text)
text = strtrim(string(text));
if ismissing(text) || strlength(text) == 0
    values = zeros(1, 0);
    return;
end
values = str2double(split(text, "|")).';
localRequire(all(isfinite(values)), ...
    "sixgr:pdsch:PhaseEvidenceInvalidEncodedNumbers", ...
    "Invalid encoded numeric vector.");
end

function text = localEncodeIntegers(values)
values = double(values(:).');
if isempty(values)
    text = "";
else
    text = strjoin(compose("%.0f", values), "|");
end
end

function text = localEncodeNumbers(values)
values = double(values(:).');
if isempty(values)
    text = "";
else
    tokens = arrayfun(@(x) string(sprintf("%.17g", x)), ...
        values, "UniformOutput", false);
    text = strjoin([tokens{:}], "|");
end
end

function bits = localBits(text)
characters = char(string(text));
bits = int8(characters(:) - '0');
end

function mismatch = localSetMismatch(actual, expected)
actual = double(actual(:).');
expected = double(expected(:).');
mismatch = numel(setdiff(actual, expected)) ...
    + numel(setdiff(expected, actual));
end

function digest = localDigest(value)
if isnumeric(value) || islogical(value)
    payload = struct( ...
        "Class", class(value), ...
        "Size", double(size(value)), ...
        "Real", double(real(value(:))).', ...
        "Imaginary", double(imag(value(:))).');
elseif isstring(value) || ischar(value)
    payload = struct( ...
        "Class", class(value), ...
        "Size", double(size(value)), ...
        "Text", string(value(:)).');
elseif isstruct(value)
    payload = orderfields(value);
else
    error("sixgr:pdsch:PhaseEvidenceDigestUnsupported", ...
        "Cannot digest a value of class %s.", class(value));
end
bytes = uint8(unicode2native(jsonencode(payload), "UTF-8"));
digest = string(sixgr.util.sha256Hex(bytes));
end

function digest = localRawInt8Digest(value)
bytes = typecast(int8(value(:)), "uint8");
digest = string(sixgr.util.sha256Hex(bytes));
end

function digest = localRawComplexDigest(value)
value = complex(double(value(:)));
interleaved = reshape([real(value).'; imag(value).'], [], 1);
bytes = typecast(interleaved, "uint8");
digest = string(sixgr.util.sha256Hex(bytes));
end

function digest = localFileDigest(path)
fid = fopen(path, "rb");
localRequire(fid >= 0, ...
    "sixgr:pdsch:PhaseEvidenceOracleArtifactUnreadable", ...
    "Cannot read oracle artifact: %s", path);
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid, inf, "*uint8");
digest = string(sixgr.util.sha256Hex(bytes));
clear cleanup
end

function localRequire(condition, identifier, message, varargin)
if ~condition
    error(identifier, message, varargin{:});
end
end
