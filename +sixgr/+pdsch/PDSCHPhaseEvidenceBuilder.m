function tf = localShouldMaterializeAssignmentMCS(row)
profile = lower(strtrim(string(row.Profile)));
switch profile
    case {"connected_strict","ra_si_strict"}
        tf = localTruth(row.DecodedDCIPresent) ...
            && localTruth(row.DCICRCPass) ...
            && localTruth(row.DCIRNTIMatch) ...
            && localTruth(row.ActiveBWPContextPresent) ...
            && localTruth(row.UEContextEpochCurrent) ...
            && localTruth(row.ServingCellActive) ...
            && localTruth(row.ResourceAvailable) ...
            && localTruth(row.MCSContextSupported) ...
            && localTruth(row.HARQContextConsistent) ...
            && localTruth(row.DCIFieldsInRange) ...
            && localTruth(row.TCIStateActive) ...
            && localValidAssignmentDCIRNTIProcedure( ...
                row.DCIFormat,row.RNTIType);
    case "sps_strict"
        tf = strlength(strtrim(string(row.SPSActivationDCIId))) > 0 ...
            && localTruth(row.SPSActivationDCICRCPass) ...
            && localTruth(row.SPSActivationDCIRNTIMatch) ...
            && localTruth(row.SPSConfigPresent) ...
            && localTruth(row.SPSActivated) ...
            && ~localTruth(row.SPSReleased) ...
            && localTruth(row.SPSOccasionMatch) ...
            && localTruth(row.ResourceAvailable) ...
            && localTruth(row.HARQContextConsistent);
    case "phy_calibration"
        tf = localTruth(row.ResourceAvailable);
    otherwise
        tf = false;
end
end

function tf = localValidAssignmentDCIRNTIProcedure(format,rntiType)
format = upper(strtrim(string(format)));
rntiType = upper(strtrim(string(rntiType)));
if rntiType == "C-RNTI"
    tf = any(format == ["1_0","1_1","1_2","1_3"]);
elseif any(rntiType == ["CS-RNTI","MCS-C-RNTI"])
    tf = any(format == ["1_0","1_1","1_2"]);
elseif any(rntiType == ["SI-RNTI","P-RNTI","RA-RNTI","TC-RNTI"])
    tf = format == "1_0";
else
    tf = false;
end
end

