    "sixgr:pdsch:PhaseEvidenceReservedCodingRoundTripFailure", ...
    ["%s aligned reserved-resource DL-SCH execution failed CRC " ...
    "or %d transport-block bits."], caseID, bitMismatch);
row = struct( ...
    "CaseID", caseID, "Codeword", 0, ...
    "TBS", double(plan.TransportBlockSize), ...
    "TBCRCType", plan.TBCRCType, ...
    "TBCRCLength", double(plan.TBCRCLength), ...
    "BaseGraph", double(plan.BaseGraph), ...
    "NumCodeBlocks", double(plan.NumCodeBlocks), ...
    "CodeBlockCRCType", plan.CBCRCType, ...
    "LiftingSize", double(plan.LiftingSize), ...
    "K", double(plan.CodeBlockLength), ...
    "N", double(plan.MotherCodeLength), ...
    "Ncb", double(plan.Ncb), ...
