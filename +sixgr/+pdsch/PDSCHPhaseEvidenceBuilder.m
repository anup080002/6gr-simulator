function [ownershipRows, mappingRows, codingRows, negatives, evidence] = ...
        localBuildResources(root)
vectors = localReadStrings(fullfile(root, ...
    "pdsch_reserved_re_test_vectors.csv"));
ownershipRows = cell(0, 1);
codingRows = cell(0, 1);
negatives = cell(0, 1);
expectedRecords = strings(0, 1);
actualRecords = strings(0, 1);
for i = 1:height(vectors)
    row = vectors(i, :);
    allocation = localDecodeIntegers(row.AllocationRE);
    sourceTexts = [row.SSBRE,row.CORESETRE,row.NZPCSIRSRE, ...
        row.ZPCSIRSRE,row.LTECRSRE,row.RateMatchPatternRE];
    reservations = struct( ...
        "SSB", localDecodeIntegers(sourceTexts(1)), ...
        "CORESET", localDecodeIntegers(sourceTexts(2)), ...
        "NZPCSIRS", localDecodeIntegers(sourceTexts(3)), ...
        "ZPCSIRS", localDecodeIntegers(sourceTexts(4)), ...
        "LTECRS", localDecodeIntegers(sourceTexts(5)), ...
        "RateMatchPattern", localDecodeIntegers(sourceTexts(6)));
    diagnostic = sixgr.pdsch.PDSCHResourceOwnershipMap.analyze( ...
        allocation, reservations);
    oracle = sixgr.pdsch.oracle.ReservedREUnionSpec.resolveEncoded( ...
        row.AllocationRE, sourceTexts);
    localRequire(diagnostic.Status == oracle.Status ...
        && isequal(diagnostic.ReservedUnionIndices, ...
            oracle.ReservedUnionIndices) ...
        && isequal(diagnostic.DataIndices, oracle.DataIndices), ...
        "sixgr:pdsch:PhaseEvidenceReservationMismatch", ...
        "Production/oracle reservation mismatch for %s.", row.CaseID);
    if row.ExpectedStatus == "ERROR"
        actualError = localCapture(@() ...
            sixgr.pdsch.PDSCHResourceOwnershipMap( ...
            allocation, reservations));
        expectedError = "sixgr:pdsch:" + row.ExpectedError;
        localRequire(actualError == expectedError, ...
            "sixgr:pdsch:PhaseEvidenceReservationErrorMismatch", ...
            "%s expected %s but observed %s.", ...
            row.CaseID, expectedError, actualError);
        negatives{end + 1, 1} = localNegativeRow( ... %#ok<AGROW>
            row.CaseID, "reserved_re_union", expectedError, actualError);
        continue;
    end

    map = sixgr.pdsch.PDSCHResourceOwnershipMap( ...
        allocation, reservations);
    [K, symbolsPerSlot] = localDecodeFrozenGridShape(allocation);
    localRequire(isfinite(K) && isfinite(symbolsPerSlot), ...
        "sixgr:pdsch:PhaseEvidenceGridDecodeFailure", ...
        "Cannot decode the frozen RE grid for %s.", row.CaseID);
    for j = 1:height(map.Entries)
        index = double(map.Entries.Index0Based(j));
        subcarrierAbsolute = mod(index, K);
        source = string(map.Entries.ReservationSources(j));
        if strlength(source) == 0
            source = "PDSCH_ALLOCATION";
        end
        ownershipRows{end + 1, 1} = struct( ... %#ok<AGROW>
            "CaseID", row.CaseID, "Slot", 0, ...
            "PRB", floor(subcarrierAbsolute / 12), ...
            "Symbol", floor(index / K), ...
            "Subcarrier", mod(subcarrierAbsolute, 12), ...
            "Owner", map.Entries.Owner(j), ...
            "SourceResourceId", source, ...
            "OwnerPriority", map.Entries.ReservationSourceCount(j), ...
            "CollisionCount", map.Entries.CollisionCount(j), ...
