function [K, symbolsPerSlot] = localDecodeFrozenGridShape(allocation)
% Decode an explicit zero-based normal/extended-CP grid without a
% full-slot fallback. The frozen resource vectors encode the complete
% allocation and therefore must resolve to exactly one NR slot shape.
K = NaN;
symbolsPerSlot = NaN;
allocation = double(allocation(:));
if isempty(allocation) || min(allocation) ~= 0 ...
        || numel(unique(allocation)) ~= numel(allocation)
    return;
end
totalRE = max(allocation) + 1;
candidateSymbols = [12 14];
candidateK = totalRE ./ candidateSymbols;
valid = candidateK == floor(candidateK) ...
    & mod(candidateK, 12) == 0;
if nnz(valid) ~= 1
    return;
end
symbolsPerSlot = candidateSymbols(valid);
K = candidateK(valid);
end

