function value = localMeanCPE(observed, reference, mask)
if ~any(mask, "all")
    value = 0;
    return;
end
symbols = find(any(mask, 1));
angles = zeros(numel(symbols), 1);
for i = 1:numel(symbols)
    symbol = symbols(i);
    active = mask(:, symbol);
    angles(i) = abs(angle(sum(observed(active, symbol) ...
        .* conj(reference(active, symbol)))));
end
value = rad2deg(mean(angles));
end

function value = localEVM(observed, reference)
if isempty(observed)
    value = 0;
    return;
end
value = 100 * sqrt(mean(abs(observed(:) - reference(:)).^2) ...
    / max(mean(abs(reference(:)).^2), eps));
end

