    "GridNumPRB", K / 12, ...
    "GridSymbolsPerSlot", symbolsPerSlot, ...
    "BWPStartPRB", 0, "AbsoluteSlot", 0, ...
    "UnavailableIndices", zeros(1, 0), ...
    "DMRSIndicesPerPort", {{zeros(1, 0)}}, ...
    "PTRSIndicesPerPort", {{zeros(1, 0)}}, ...
    "DMRSLogicalPortSet", 0, ...
    "PTRSLogicalPortSet", 0, ...
    "LayerCountPerCodeword", 1, ...
    "QmPerCodeword", 2, ...
