function spec = localPrecoderSpec(row)
nPorts = localNumber(row.NPorts);
nLayers = localNumber(row.NLayers);
nPRG = localNumber(row.NPRG);
nGroups = localNumber(row.NSymbolGroups);
shape = localPrecoderShape(row.MatrixShape);
if isempty(shape)
    W = 7;
else
    W = localPrecoderMatrix(shape, row.ExpectedStatus == "PASS");
end
scheduledSymbols = 0:11;
symbolGroupMap = floor((0:numel(scheduledSymbols)-1) ...
    * nGroups / numel(scheduledSymbols));
spec = struct( ...
    "Mode", row.Mode, "NPorts", nPorts, "NLayers", nLayers, ...
    "NPRG", nPRG, "NSymbolGroups", nGroups, ...
    "PRGSize", localNumber(row.PRGSize), ...
    "PRBSet", localPRBSet(row.PRBSet), ...
    "ScheduledSymbols", scheduledSymbols, ...
    "SymbolGroupMap", symbolGroupMap, "W", W, ...
    "MatrixSource", "frozen_precoding_vector:" + row.CaseID, ...
    "CodebookIdentifier", "frozen:" + row.Mode, ...
    "NormalizationConvention", "semi_unitary", ...
    "NormalizationTolerance", 2e-12);
end

function shape = localPrecoderShape(text)
if text == "scalar"
    shape = [];
else
    shape = str2double(split(text, "x")).';
end
end

function W = localPrecoderMatrix(shape, makeValid)
W = complex(zeros(shape));
if ~makeValid
    return;
end
nPorts = shape(1);
nLayers = shape(2);
for prg = 1:shape(3)
    for group = 1:shape(4)
        row = (0:nPorts-1).';
        column = 0:nPorts-1;
        unitary = exp(-1j * 2*pi * row * column / nPorts) ...
            / sqrt(nPorts);
        phase = exp(1j * (0:nPorts-1).' ...
            * (prg + 2*group) / 17);
        W(:,:,prg,group) = diag(phase) ...
            * unitary(:, 1:nLayers);
    end
end
end

function value = localPRBSet(text)
if contains(text, "-")
    limits = str2double(split(text, "-"));
    value = limits(1):limits(2);
else
    value = str2double(split(text, "|")).';
end
end

function [prb, symbol] = localOneResourcePerSlice(bundle)
count = bundle.NPRG * bundle.NSymbolGroups;
prb = zeros(1, count);
symbol = zeros(1, count);
position = 0;
for group = 0:(bundle.NSymbolGroups - 1)
    selectedSymbol = bundle.ScheduledSymbols( ...
        find(bundle.SymbolGroupIndexPerSymbol == group, 1));
    for prg = 0:(bundle.NPRG - 1)
        position = position + 1;
        prb(position) = bundle.PRGToPRBMap{prg + 1}(1);
        symbol(position) = selectedSymbol;
    end
end
end

