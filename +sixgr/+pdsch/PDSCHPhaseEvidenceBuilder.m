function text = localText(value)
if islogical(value) && isscalar(value)
    text = string(double(value));
elseif isnumeric(value) && isscalar(value)
    if isnan(value)
        text = "";
    else
        text = string(sprintf("%.17g", double(value)));
    end
elseif ischar(value)
    text = string(value);
elseif isstring(value) && isscalar(value)
    text = value;
elseif isnumeric(value) || islogical(value)
    text = localEncodeNumbers(value);
elseif isstring(value)
    text = strjoin(value(:).', "|");
else
    error("sixgr:pdsch:PhaseEvidenceUnsupportedCellValue", ...
        "Cannot serialize contract value of class %s.", class(value));
