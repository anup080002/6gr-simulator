ndi = double(ndi(:).');
rv = double(rv(:).');
newData = logical(newData(:).');
localRequire(numel(ndi) == count && numel(rv) == count ...
        && numel(newData) == count ...
        && iscell(transportBlocks) && numel(transportBlocks) == count, ...
    "sixgr:pdsch:PhaseEvidenceHARQCodewordInputMismatch", ...
    "Canonical HARQ execution requires exact per-codeword inputs.");

request = base.AssignmentRequest;
request.NDIPerCodeword = ndi;
request.RVPerCodeword = rv;
assignment = sixgr.pdsch.PDSCHAssignmentFactory.forCalibration( ...
    request, struct("AbsoluteSlot", 0, "ResourceAvailable", true));
if count == 1
    transmitterInput = transportBlocks{1};
else
    transmitterInput = transportBlocks;
end
transmitter = sixgr.pdsch.PDSCHTransmitter( ...
    transmitterInput, assignment, base.ResourcePlan, base.Carrier, ...
    base.ReferenceConfig, "PrecoderBundle", base.PrecoderBundle);

identity = strings(1, count);
for cw = 1:count
    identity(cw) = localRawInt8Digest(transportBlocks{cw});
end
receiverConfig = base.ReceiverConfig;
receiverConfig.TransportBlockSizes = ...
    cellfun(@numel, transportBlocks);
receiverConfig.NewDataPerCodeword = newData;
receiverConfig.TBIdentityDigestPerCodeword = identity;
receiver = sixgr.pdsch.PDSCHReceiver( ...
    transmitter.Waveform, assignment, base.ResourcePlan, ...
    base.Carrier, base.ReferenceConfig, receiverConfig, ...
    "CodingPlans", transmitter.CodingPlans, ...
    "PrecoderBundle", base.PrecoderBundle, ...
    "HARQManager", manager);
localRequire(transmitter.Source ...
        == "explicit_pdsch_dlsch_production_chain" ...
        && receiver.Source ...
        == "explicit_pdsch_dlsch_production_receiver" ...
        && numel(receiver.HARQResults) == count ...
        && all(receiver.CRCPassPerCodeword), ...
    "sixgr:pdsch:PhaseEvidenceHARQProductionExecutionFailed", ...
    "Canonical no-noise PDSCH HARQ TX/RX execution did not pass.");

observations = cell(1, count);
results = receiver.HARQResults;
contexts = cell(1, count);
for cw = 1:count
    plan = transmitter.CodingPlans{cw};
    if count == 1
        decoded = receiver.Decode;
    else
        decoded = receiver.Decode.Codewords{cw};
    end
    recovered = double(decoded.RateRecoveredLLR);
    nref = plan.Nref;
    if isempty(nref)
        nref = plan.Ncb;
    end
    observations{cw} = struct( ...
        "UEId", double(assignment.get("UEId")), ...
        "ServingCellId", double(assignment.get("ServingCellId")), ...
        "SchedulingCellId", double(assignment.get("SchedulingCellId")), ...
        "CCId", double(assignment.get("CCId")), ...
        "BWPId", double(assignment.get("BWPId")), ...
        "HARQProcessId", double(assignment.get("HARQProcessId")), ...
        "CodewordIndex", cw - 1, ...
        "ConfigurationEpoch", ...
            double(assignment.get("ConfigurationEpoch")), ...
