function metrics = localPTRSMetrics(row, resolved, indices0)
execution = localPTRSProductionExecution(row, resolved, indices0);
carrier = execution.Carrier;
reference = execution.Transmitter.Grid;
K = size(reference, 1);
L = size(reference, 2);

% A fixed seeded oscillator random walk is an actual symbol-wise
% phase-noise impairment of the emitted canonical production grid.  It is
% deterministic only so the evidence artifact is reproducible.
seed = 12001 + 31 * localNumber(row.TimeDensity) ...
    + 17 * localNumber(row.FrequencyDensity) ...
    + sum(double(char(row.REOffset)));
stream = RandStream("mt19937ar", "Seed", seed);
unitTrajectory = cumsum(randn(stream, 1, L));
severity = 0.035;
phase = severity .* unitTrajectory;
impaired = reference .* reshape(exp(1j * phase), 1, L, 1);

indices1 = double(execution.Transmitter.PTRSIndices(:)) + 1;
ptrsSymbols = complex(zeros(0, 1));
if ~isempty(indices1)
    ptrsSymbols = execution.Transmitter.PTRSPortSymbols(1, :).';
end
[corrected, ~, info] = sixgr.phy.rx.correctCPEFromPTRS( ...
    impaired, indices1, ptrsSymbols, carrier);
if resolved.Present
    localRequire(info.Enabled ...
            && info.NumSymbolsCorrected == ...
                numel(unique(floor(double(indices0(:)) / K))), ...
        "sixgr:pdsch:PhaseEvidencePTRSCorrectionDisabled", ...
        "Production PT-RS correction did not execute on every PT-RS symbol.");
else
    localRequire(~info.Enabled && isempty(indices1), ...
        "sixgr:pdsch:PhaseEvidenceUnexpectedPTRSCorrection", ...
        "A PT-RS-absent production execution unexpectedly enabled correction.");
end

measure = false(K, L);
measure(execution.ResourcePlan.DataIndices + 1) = true;
if ~isempty(indices1)
    [~, symbols] = ind2sub([K L], indices1);
    symbolMask = false(1, L);
    symbolMask(unique(symbols)) = true;
    measure = measure & repmat(symbolMask, K, 1);
end
localRequire(any(measure, "all"), ...
    "sixgr:pdsch:PhaseEvidencePTRSNoMeasuredData", ...
    "Production PT-RS execution has no emitted PDSCH data RE to measure.");
metrics = struct( ...
    "CPEBeforeDeg", localMeanCPE(impaired, reference, measure), ...
    "CPEAfterDeg", localMeanCPE(corrected, reference, measure), ...
    "EVMBeforePercent", localEVM(impaired(measure), reference(measure)), ...
    "EVMAfterPercent", localEVM(corrected(measure), reference(measure)));
localRequire(all(isfinite(struct2array(metrics))) ...
    && abs(metrics.CPEAfterDeg) <= abs(metrics.CPEBeforeDeg) + 1e-9 ...
    && metrics.EVMAfterPercent <= metrics.EVMBeforePercent + 1e-9, ...
    "sixgr:pdsch:PhaseEvidencePTRSMetricsInvalid", ...
    "Production PT-RS correction produced invalid or degraded metrics.");
end

