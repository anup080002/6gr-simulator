classdef PDSCHIntegrationValidator
    %PDSCHINTEGRATIONVALIDATOR Bind assignment to active BWP/CC/TCI truth.

    methods (Static)
        function binding = bind(assignment, context, precoderBundle)
            arguments
                assignment (1,1) sixgr.pdsch.PDSCHSchedulingAssignment
                context (1,1) struct
                precoderBundle = []
            end
            requirePrecoderBinding = nargin >= 3;
            required = [ ...
                "ActiveServingCellIds","ActiveCCIds","ActiveBWPId", ...
                "ActiveBWPStartPRB","ActiveBWPNumPRB","ConfigurationEpoch", ...
                "CarrierIndicatorValid","CrossCarrierSchedulingEnabled", ...
                "ActivatedTCIStates"];
            missing = required(~isfield(context, required));
            if ~isempty(missing)
                error("sixgr:pdsch:IncompleteIntegrationContext", ...
                    "PDSCH integration context is missing: %s.", ...
                    strjoin(cellstr(missing), ", "));
            end
            sixgr.pdsch.PDSCHIntegrationValidator. ...
                validateContextShape(context);
            assignmentDigest = assignment.validateForExecution();
            data = assignment.toStruct();
            if ~ismember(double(data.ServingCellId), ...
                    double(context.ActiveServingCellIds(:)))
                error("sixgr:pdsch:InactiveServingCell", ...
                    "Scheduled serving cell is inactive.");
            end
            if ~ismember(double(data.CCId), double(context.ActiveCCIds(:)))
                error("sixgr:pdsch:InactiveComponentCarrier", ...
                    "Scheduled component carrier is inactive.");
            end
            if double(data.BWPId) ~= double(context.ActiveBWPId)
                error("sixgr:pdsch:MissingActiveBWPContext", ...
                    "Assignment BWP does not match the active DL BWP.");
            end
            if double(data.ConfigurationEpoch) ~= double(context.ConfigurationEpoch)
                error("sixgr:pdsch:StaleUEConfigurationEpoch", ...
                    "Assignment configuration epoch is stale.");
            end
            if ~logical(context.CarrierIndicatorValid)
                error("sixgr:pdsch:InvalidCarrierIndicator", ...
                    "Decoded carrier indicator does not identify the scheduled CC.");
            end
            crossCarrier = double(data.SchedulingCellId) ~= double(data.ServingCellId);
            if crossCarrier && ~logical(context.CrossCarrierSchedulingEnabled)
                error("sixgr:pdsch:CrossCarrierSchedulingNotConfigured", ...
                    "Scheduling and scheduled cells differ without cross-carrier configuration.");
            end
            bwpRelative = double(data.PRBSetBWPRelative(:).');
            if isempty(bwpRelative) || any(bwpRelative < 0) || ...
                    any(bwpRelative >= double(context.ActiveBWPNumPRB))
                error("sixgr:pdsch:ResourceOutsideBWP", ...
                    "Assignment PRBs lie outside the active BWP.");
            end
            expectedCarrier = double(context.ActiveBWPStartPRB) + bwpRelative;
            if ~isequal(expectedCarrier, double(data.PRBSetCarrierRelative(:).'))
                error("sixgr:pdsch:BWPToCarrierPRBMappingMismatch", ...
                    "Carrier-relative PRBs do not equal BWP start plus BWP-relative PRBs.");
            end
            if isfinite(data.PDCCHAbsoluteSlot) && ...
                    double(data.PDCCHAbsoluteSlot) + double(data.K0) ~= ...
                    double(data.PDSCHAbsoluteSlot)
                error("sixgr:pdsch:InvalidK0Timing", ...
                    "PDSCH absolute slot does not equal PDCCH slot plus K0.");
            end
            tci = sixgr.pdsch.PDSCHIntegrationValidator. ...
                resolveTCI(context.ActivatedTCIStates, data.TCIStateId);
            precoderBinding = struct( ...
                "Required", false, ...
                "PrecoderContextId", "", ...
                "PrecoderBundleDigest", "", ...
                "TCIStateId", double(tci.TCIStateId), ...
                "AssignmentId", string(data.AssignmentId), ...
                "ConfigurationEpoch", double(data.ConfigurationEpoch), ...
                "Status", "NOT_EVALUATED");
            if requirePrecoderBinding
                precoderBinding = sixgr.pdsch.PDSCHIntegrationValidator. ...
                    validatePrecoderContext( ...
                    tci, precoderBundle, assignmentDigest, data);
            end
            namespace = struct( ...
                "ServingCellId", double(data.ServingCellId), ...
                "SchedulingCellId", double(data.SchedulingCellId), ...
                "CCId", double(data.CCId), ...
                "BWPId", double(data.BWPId), ...
                "HARQProcessId", double(data.HARQProcessId), ...
                "AssignmentId", string(data.AssignmentId));
            binding = struct( ...
                "AssignmentId", string(data.AssignmentId), ...
                "AssignmentValidationDigest", string(assignmentDigest), ...
                "ConfigurationEpoch", double(data.ConfigurationEpoch), ...
                "CrossCarrier", logical(crossCarrier), ...
                "PRBSetBWPRelative", bwpRelative, ...
                "PRBSetCarrierRelative", expectedCarrier, ...
                "PDSCHAbsoluteSlot", double(data.PDSCHAbsoluteSlot), ...
                "Namespace", namespace, ...
                "TCIState", tci, ...
                "ReceiverQCL", struct( ...
                    "TCIStateId", double(tci.TCIStateId), ...
                    "SourceReferenceSignal", string(tci.SourceReferenceSignal), ...
                    "SourceReferenceSignalId", string(tci.SourceReferenceSignalId), ...
                    "QCLTypes", string(tci.QCLTypes), ...
                    "Assumptions", string(tci.Assumptions)), ...
                "PrecoderBinding", precoderBinding, ...
                "IntegrationContextDigest", ...
                    sixgr.pdsch.PDSCHIntegrationValidator.contextDigest(context), ...
                "Status", "PASS");
            binding.BindingDigest = ...
                sixgr.pdsch.PDSCHIntegrationValidator.bindingDigest(binding);
        end

        function plan = transmissionOccasions(assignment, binding, specification)
            arguments
                assignment (1,1) sixgr.pdsch.PDSCHSchedulingAssignment
                binding (1,1) struct
                specification (1,1) struct
            end
            sixgr.pdsch.PDSCHIntegrationValidator. ...
                validateBindingForAssignment(assignment, binding);
            required = ["Scheme","TRPs","TBIdentityDigest","HARQProcessId"];
            missing = required(~isfield(specification, required));
            if ~isempty(missing)
                error("sixgr:pdsch:IncompleteMultiTRPSpecification", ...
                    "Multi-TRP specification is missing: %s.", ...
                    strjoin(cellstr(missing), ", "));
            end
            scheme = lower(strtrim(string(specification.Scheme)));
            if ~any(scheme == ["single_trp","repetition_noncoherent"])
                error("sixgr:pdsch:UnsupportedMultiTRPScheme", ...
                    "Unsupported multi-TRP PDSCH scheme '%s'.", scheme);
            end
            trps = specification.TRPs;
            if ~isstruct(trps)
                error("sixgr:pdsch:IncompleteMultiTRPSpecification", ...
                    "TRPs must be a struct vector.");
            end
            requiredCount = 1 + double(scheme == "repetition_noncoherent");
            if numel(trps) ~= requiredCount
                error("sixgr:pdsch:UnsupportedMultiTRPCombination", ...
                    "Scheme '%s' requires exactly %d transmission occasion(s).", ...
                    scheme, requiredCount);
            end
            data = assignment.toStruct();
            if double(specification.HARQProcessId) ~= double(data.HARQProcessId)
                error("sixgr:pdsch:MultiTRPHARQIdentityMismatch", ...
                    "Multi-TRP HARQ process does not match the assignment.");
            end
            occasionTemplate = struct( ...
                "OccasionIndex", NaN, "TRPId", NaN, "TCIStateId", NaN, ...
                "AbsoluteSlot", NaN, "SymbolAllocation", [], "PRBSet", [], ...
                "PrecoderBundle", [], "DMRSPTRSPlan", struct(), ...
                "PowerScaling", NaN, "TBIdentityDigest", "", ...
                "HARQProcessId", NaN, "CombinationRule", "");
            occasions = repmat(occasionTemplate, 1, requiredCount);
            for idx = 1:requiredCount
                trp = trps(idx);
                fields = ["TRPId","TCIStateId","SlotOffset","PrecoderBundle", ...
                    "DMRSPTRSPlan","PowerScaling","TBIdentityDigest", ...
                    "HARQProcessId"];
                missingTRP = fields(~isfield(trp, fields));
                if ~isempty(missingTRP)
                    error("sixgr:pdsch:IncompleteMultiTRPSpecification", ...
                        "TRP occasion %d is missing: %s.", idx - 1, ...
                        strjoin(cellstr(missingTRP), ", "));
                end
                if string(trp.TBIdentityDigest) ~= ...
                        string(specification.TBIdentityDigest) || ...
                        double(trp.HARQProcessId) ~= ...
                        double(specification.HARQProcessId)
                    error("sixgr:pdsch:MultiTRPHARQIdentityMismatch", ...
                        "TRP occasions must share exact TB/HARQ identity.");
                end
                if ~(isa(trp.PrecoderBundle, ...
                        "sixgr.pdsch.PDSCHPrecoderBundle"))
                    error("sixgr:pdsch:MissingPrecoderBundle", ...
                        "Every TRP occasion requires an applied precoder bundle.");
                end
                if ~(isscalar(trp.PowerScaling) && isfinite(trp.PowerScaling) ...
                        && trp.PowerScaling > 0)
                    error("sixgr:pdsch:InvalidTRPPowerScaling", ...
                        "TRP power scaling must be positive and finite.");
                end
                occasions(idx) = occasionTemplate;
                occasions(idx).OccasionIndex = idx - 1;
                occasions(idx).TRPId = double(trp.TRPId);
                occasions(idx).TCIStateId = double(trp.TCIStateId);
                occasions(idx).AbsoluteSlot = double(data.PDSCHAbsoluteSlot) ...
                    + double(trp.SlotOffset);
                occasions(idx).SymbolAllocation = ...
                    double(data.SymbolAllocation(:).');
                occasions(idx).PRBSet = ...
                    double(data.PRBSetCarrierRelative(:).');
                occasions(idx).PrecoderBundle = trp.PrecoderBundle;
                occasions(idx).DMRSPTRSPlan = trp.DMRSPTRSPlan;
                occasions(idx).PowerScaling = double(trp.PowerScaling);
                occasions(idx).TBIdentityDigest = ...
                    string(trp.TBIdentityDigest);
                occasions(idx).HARQProcessId = double(trp.HARQProcessId);
                occasions(idx).CombinationRule = ...
                    "soft_llr_sum_after_per_occasion_equalization";
            end
            plan = struct( ...
                "Scheme", scheme, ...
                "AssignmentId", assignment.AssignmentId, ...
                "TBIdentityDigest", string(specification.TBIdentityDigest), ...
                "HARQProcessId", double(specification.HARQProcessId), ...
                "Occasions", occasions, ...
                "CombinationRule", ...
                    "soft_llr_sum_after_per_occasion_equalization", ...
                "Status", "PASS");
        end

        function combined = combineOccasionLLR(llrPerOccasion, plan)
            arguments
                llrPerOccasion (1,:) cell
                plan (1,1) struct
            end
            if numel(llrPerOccasion) ~= numel(plan.Occasions)
                error("sixgr:pdsch:MultiTRPOccasionCountMismatch", ...
                    "LLR observation count differs from the transmission plan.");
            end
            lengths = cellfun(@numel, llrPerOccasion);
            if isempty(lengths) || any(lengths ~= lengths(1))
                error("sixgr:pdsch:MultiTRPLLRLayoutMismatch", ...
                    "All TRP LLR observations must share one coding layout.");
            end
            combined = zeros(size(llrPerOccasion{1}));
            for idx = 1:numel(llrPerOccasion)
                values = double(llrPerOccasion{idx});
                if any(~isfinite(values(:)))
                    error("sixgr:pdsch:MultiTRPInvalidLLR", ...
                        "TRP LLR observations must be finite.");
                end
                combined = combined + values;
            end
        end
    end

    methods (Static, Access = private)
        function validateContextShape(context)
            integerVectors = ["ActiveServingCellIds","ActiveCCIds"];
            for field = integerVectors
                raw = context.(char(field));
                values = double(raw(:));
                if isempty(values) || any(~isfinite(values)) ...
                        || any(values ~= fix(values)) || any(values < 0)
                    error("sixgr:pdsch:InvalidIntegrationContext", ...
                        "%s must contain nonempty nonnegative integer IDs.", ...
                        field);
                end
            end
            scalarFields = ["ActiveBWPId","ActiveBWPStartPRB", ...
                "ActiveBWPNumPRB","ConfigurationEpoch"];
            for field = scalarFields
                value = double(context.(char(field)));
                if ~(isscalar(value) && isfinite(value) ...
                        && value == fix(value) && value >= 0)
                    error("sixgr:pdsch:InvalidIntegrationContext", ...
                        "%s must be a nonnegative integer scalar.", field);
                end
            end
            if double(context.ActiveBWPNumPRB) < 1
                error("sixgr:pdsch:InvalidIntegrationContext", ...
                    "ActiveBWPNumPRB must be positive.");
            end
            logicalFields = ["CarrierIndicatorValid", ...
                "CrossCarrierSchedulingEnabled"];
            for field = logicalFields
                value = context.(char(field));
                if ~(islogical(value) && isscalar(value))
                    error("sixgr:pdsch:InvalidIntegrationContext", ...
                        "%s must be an explicit logical scalar.", field);
                end
            end
            if ~isstruct(context.ActivatedTCIStates) ...
                    || isempty(context.ActivatedTCIStates)
                error("sixgr:pdsch:InvalidIntegrationContext", ...
                    "ActivatedTCIStates must be a nonempty struct vector.");
            end
        end

        function precoderBinding = validatePrecoderContext( ...
                tci, precoderBundle, assignmentDigest, assignmentData)
            if ~isa(precoderBundle, "sixgr.pdsch.PDSCHPrecoderBundle")
                error("sixgr:pdsch:MissingPrecoderTCIBinding", ...
                    "Strict integrated PDSCH execution requires an explicit " + ...
                    "PDSCHPrecoderBundle bound to the selected TCI state.");
            end
            required = ["PrecoderContextId","PrecoderBundleDigest", ...
                "PrecoderAssignmentId","PrecoderAssignmentValidationDigest", ...
                "PrecoderConfigurationEpoch"];
            missing = required(~isfield(tci, required));
            if ~isempty(missing)
                error("sixgr:pdsch:MissingPrecoderTCIBinding", ...
                    "Selected TCI state is missing precoder binding field(s): %s.", ...
                    strjoin(cellstr(missing), ", "));
            end
            contextId = string(tci.PrecoderContextId);
            expectedBundleDigest = string(tci.PrecoderBundleDigest);
            expectedAssignmentId = string(tci.PrecoderAssignmentId);
            expectedAssignmentDigest = ...
                string(tci.PrecoderAssignmentValidationDigest);
            expectedEpoch = double(tci.PrecoderConfigurationEpoch);
            if strlength(strtrim(contextId)) == 0 ...
                    || strlength(strtrim(expectedBundleDigest)) == 0 ...
                    || strlength(strtrim(expectedAssignmentId)) == 0 ...
                    || strlength(strtrim(expectedAssignmentDigest)) == 0 ...
                    || ~(isscalar(expectedEpoch) && isfinite(expectedEpoch) ...
                    && expectedEpoch == fix(expectedEpoch))
                error("sixgr:pdsch:MissingPrecoderTCIBinding", ...
                    "Selected TCI state contains an incomplete precoder binding.");
            end
            if expectedBundleDigest ~= precoderBundle.ImmutableBundleDigest ...
                    || expectedAssignmentId ~= ...
                        string(assignmentData.AssignmentId) ...
                    || expectedAssignmentDigest ~= string(assignmentDigest) ...
                    || expectedEpoch ~= ...
                        double(assignmentData.ConfigurationEpoch)
                error("sixgr:pdsch:StalePrecoderTCIContext", ...
                    "Applied PDSCH precoder, selected TCI state, assignment, " + ...
                    "or configuration epoch does not match the active binding.");
            end
            precoderBinding = struct( ...
                "Required", true, ...
                "PrecoderContextId", contextId, ...
                "PrecoderBundleDigest", precoderBundle.ImmutableBundleDigest, ...
                "TCIStateId", double(tci.TCIStateId), ...
                "AssignmentId", string(assignmentData.AssignmentId), ...
                "AssignmentValidationDigest", string(assignmentDigest), ...
                "ConfigurationEpoch", ...
                    double(assignmentData.ConfigurationEpoch), ...
                "Status", "PASS");
        end

        function validateBindingForAssignment(assignment, binding)
            required = ["AssignmentId","AssignmentValidationDigest", ...
                "ConfigurationEpoch","BindingDigest"];
            missing = required(~isfield(binding, required));
            if ~isempty(missing)
                error("sixgr:pdsch:IntegrationBindingMismatch", ...
                    "Integration binding is missing: %s.", ...
                    strjoin(cellstr(missing), ", "));
            end
            assignmentDigest = assignment.validateForExecution();
            if string(binding.AssignmentId) ~= assignment.AssignmentId ...
                    || string(binding.AssignmentValidationDigest) ~= ...
                        string(assignmentDigest) ...
                    || double(binding.ConfigurationEpoch) ~= ...
                        double(assignment.get("ConfigurationEpoch")) ...
                    || string(binding.BindingDigest) ~= ...
                        sixgr.pdsch.PDSCHIntegrationValidator. ...
                        bindingDigest(binding)
                error("sixgr:pdsch:IntegrationBindingMismatch", ...
                    "Integration binding is stale, mutated, or belongs to a different assignment.");
            end
        end

        function digest = contextDigest(context)
            bytes = uint8(unicode2native( ...
                jsonencode(orderfields(context)), "UTF-8"));
            digest = string(sixgr.util.sha256Hex(bytes));
        end

        function digest = bindingDigest(binding)
            if isfield(binding, "BindingDigest")
                binding = rmfield(binding, "BindingDigest");
            end
            bytes = uint8(unicode2native( ...
                jsonencode(orderfields(binding)), "UTF-8"));
            digest = string(sixgr.util.sha256Hex(bytes));
        end

        function tci = resolveTCI(states, selectedId)
            if ~isstruct(states)
                error("sixgr:pdsch:TCIStateNotActivated", ...
                    "Activated TCI state collection is unavailable.");
            end
            ids = arrayfun(@(x) double(x.TCIStateId), states);
            match = find(ids == double(selectedId), 1);
            if isempty(match) || ~logical(states(match).Activated)
                error("sixgr:pdsch:TCIStateNotActivated", ...
                    "TCI state %d is unknown or inactive.", selectedId);
            end
            required = ["SourceReferenceSignal","SourceReferenceSignalId", ...
                "QCLTypes","Assumptions"];
            missing = required(~isfield(states(match), required));
            if ~isempty(missing)
                error("sixgr:pdsch:IncompleteQCLState", ...
                    "Activated TCI state is missing: %s.", ...
                    strjoin(cellstr(missing), ", "));
            end
            tci = states(match);
        end
    end
end
