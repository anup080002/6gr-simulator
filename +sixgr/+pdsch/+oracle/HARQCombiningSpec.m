function result = HARQCombiningSpec(observations)
%HARQCOMBININGSPEC Independent position-aware HARQ soft-combining oracle.
%   This function intentionally does not call PDSCHHARQManager,
%   PDSCHHARQContext, DLSCHDecoder, or production combineSoftLLR code.

if ~iscell(observations) || isempty(observations)
    error("sixgr:pdsch:oracle:HARQCombiningSpec:MissingObservations", ...
        "HARQ oracle requires a nonempty cell vector of observations.");
end
observations = observations(:).';
required = [ ...
    "NewData","NDI","RV","TBIdentityDigest","TBS", ...
    "BaseGraph","LiftingSize","CodeBlockLayout","Ncb","Nref", ...
    "RateRecoveredLLR","ValidPositionMask"];

initialized = false;
buffer = zeros(0, 1);
validPositions = false(0, 1);
identity = struct();
observationCount = 0;
combineCount = 0;
resetCount = 0;
for index = 1:numel(observations)
    observation = observations{index};
    if ~(isstruct(observation) && isscalar(observation))
        error("sixgr:pdsch:oracle:HARQCombiningSpec:InvalidObservation", ...
            "HARQ observation %d must be a scalar struct.", index - 1);
    end
    missing = required(~isfield(observation, required));
    if ~isempty(missing)
        error("sixgr:pdsch:oracle:HARQCombiningSpec:MissingField", ...
            "HARQ observation %d is missing: %s.", index - 1, ...
            strjoin(cellstr(missing), ", "));
    end

    current = double(observation.RateRecoveredLLR);
    mask = logical(observation.ValidPositionMask);
    if ~isreal(current) || isempty(current) ...
            || ~isequal(size(current), size(mask)) ...
            || any(~isfinite(current(mask)))
        error("sixgr:pdsch:oracle:HARQCombiningSpec:InvalidSoftBuffer", ...
            "HARQ observation %d has invalid position-aware LLR input.", ...
            index - 1);
    end
    if ~(islogical(observation.NewData) ...
            && isscalar(observation.NewData))
        error("sixgr:pdsch:oracle:HARQCombiningSpec:InvalidNewData", ...
            "NewData must be an explicit logical scalar.");
    end

    currentIdentity = localIdentity(observation);
    if ~initialized || observation.NewData
        buffer = zeros(size(current));
        validPositions = false(size(mask));
        identity = currentIdentity;
        initialized = true;
        resetCount = resetCount + 1;
    else
        if ~isequaln(currentIdentity, identity)
            error("sixgr:pdsch:oracle:HARQCombiningSpec:IdentityMismatch", ...
                "Retransmission identity/layout differs from the active TB.");
        end
        if ~isequal(size(current), size(buffer))
            error("sixgr:pdsch:oracle:HARQCombiningSpec:LayoutMismatch", ...
                "Retransmission circular-buffer shape changed.");
        end
        combineCount = combineCount + 1;
    end

    buffer(mask) = buffer(mask) + current(mask);
    validPositions(mask) = true;
    observationCount = observationCount + 1;
end

result = struct( ...
    "ContractVersion", "IndependentPDSCHHARQCombiningSpec/v1", ...
    "CircularBufferLLR", buffer, ...
    "ValidPositionMask", validPositions, ...
    "ObservationCount", observationCount, ...
    "CombineCount", combineCount, ...
    "ResetCount", resetCount, ...
    "TBIdentityDigest", string(identity.TBIdentityDigest), ...
    "Algorithm", "positionwise_circular_buffer_llr_sum_with_ndi_reset", ...
    "Source", "independent_pdsch_harq_combining_oracle");
end

function identity = localIdentity(observation)
layout = observation.CodeBlockLayout;
if ~(isstruct(layout) && isscalar(layout) ...
        && isfield(layout, "CombineSignature") ...
        && strlength(strtrim(string(layout.CombineSignature))) > 0)
    error("sixgr:pdsch:oracle:HARQCombiningSpec:MissingLayoutIdentity", ...
        "CodeBlockLayout must carry the RV-independent CombineSignature.");
end
identity = struct( ...
    "TBIdentityDigest", string(observation.TBIdentityDigest), ...
    "TBS", double(observation.TBS), ...
    "BaseGraph", double(observation.BaseGraph), ...
    "LiftingSize", double(observation.LiftingSize), ...
    "LayoutCombineSignature", string(layout.CombineSignature), ...
    "Ncb", double(observation.Ncb), ...
    "Nref", double(observation.Nref));
end
