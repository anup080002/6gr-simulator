    field = fields(idx);
    if ~isequal(double(actual.(field)), double(expected.(field)))
        error("sixgr:pdsch:RASIMaterializationMismatch", ...
            "Assignment materialization changed PDSCH.%s.", field);
    end
end
expectedPorts = double(expected.DMRS.DMRSPortSet);
if upper(string(actual.Modulation)) ~= upper(string(expected.Modulation)) ...
        || upper(string(actual.MappingType)) ~= upper(string(expected.MappingType)) ...
        || ~isequal(double(actual.DMRS.DMRSPortSet), expectedPorts)
    error("sixgr:pdsch:RASIMaterializationMismatch", ...
        "Assignment materialization changed modulation, mapping, or DM-RS ports.");
