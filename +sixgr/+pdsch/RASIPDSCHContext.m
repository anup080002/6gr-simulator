function tbs = localTBS(requested, assignment, carrier, pdsch)
% TS 38.214 TBS uses the standardized N_RE-per-PRB accounting, while the
% exact rate-matching G below uses the actual data indices after PT-RS and
% other reservations.  PT-RS frequency density can make actual data RE
% nonuniform across PRBs; rejecting that valid mapping conflates these two
% distinct quantities.
computed = sixgr.pdsch.TBSCalculator(carrier, pdsch, ...
    double(assignment.get("TargetCodeRatePerCodeword")), ...
    double(assignment.get("XOverhead")),double(assignment.get("TBScalingPerCodeword")));
computed = double(computed);
if isempty(requested)
    tbs = computed;
elseif double(requested) ~= computed
    error("sixgr:pdsch:RASITransportBlockSizeMismatch", ...
        "Persisted TBS=%d differs from exact assignment/resource TBS=%d.", ...
        double(requested), computed);
else
    tbs = double(requested);
end
end

