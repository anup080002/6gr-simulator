function [value,next] = localReadUInt(bits,pos,width)
if pos < 1 || width < 1 || pos + width - 1 > numel(bits)
    error("sixgr:pdsch:ProcedureDCIFieldOutOfRange", ...
        "DCI bit-field read extends beyond the payload.");
end
value = uint64(0);
for idx = 1:width
    value = bitshift(value,1) + uint64(bits(pos+idx-1) ~= 0);
end
value = double(value);
next = pos + width;
end

function [lengthRB,startRB] = localDecodeRIV(nRB,riv)
lengthRB = floor(double(riv) / nRB) + 1;
startRB = double(riv) - nRB * (lengthRB - 1);
if lengthRB > nRB - startRB
    lengthRB = nRB - lengthRB + 2;
    startRB = nRB - 1 - startRB;
end
end

