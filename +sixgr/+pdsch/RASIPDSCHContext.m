function indices = localDMRS(carrier, pdsch, ports)
sub = nrPDSCHDMRSIndices(carrier, pdsch, ...
    "IndexStyle", "subscript", "IndexBase", "0based");
K = double(carrier.NSizeGrid) * 12;
indices = cell(1, numel(ports));
for idx = 1:numel(ports)
    mask = double(sub(:,3)) == double(ports(idx));
    indices{idx} = double(sub(mask,1) + K * sub(mask,2)).';
    if isempty(indices{idx})
        error("sixgr:pdsch:RASIDMRSShapeMismatch", ...
            "No DM-RS indices were generated for logical port %d.", ...
            ports(idx));
    end
end
end

function indices = localPTRS(carrier, pdsch, rankValue)
