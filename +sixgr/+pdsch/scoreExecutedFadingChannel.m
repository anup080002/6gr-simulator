function [score,referenceValues,estimatedValues]=scoreExecutedFadingChannel(tx,rx,reference)
% Post-decode NMSE of the effective channel on actual scheduled data REs.
% Uses the same execution's sample-rate channel operator, not another LS
% estimate, a refiltered waveform, fitted gain/phase, or decoder input.
assert(isstruct(reference) && isscalar(reference) && ...
    reference.Source=="same_executed_NR_channel_path_gains_and_filters" && ...
    reference.AdditionalChannelExecutions==0 && ~reference.ReceiverEstimatorInput && ...
    ~reference.LargeScaleLossApplied && ~reference.PhysicalPortMappingApplied && ...
    ~reference.RFIncluded && reference.OutputSampleAlignment=="grant_delay_aligned", ...
    'sixgr:pdsch:InvalidExecutedScoringReference', ...
    'Retain the same executed, grant-aligned physical-port channel before scoring.');
assert(reference.CanonicalEndSampleExclusive-reference.StartSample==size(tx.Waveform,1) && ...
    string(reference.InputWaveformSHA256)==string( ...
    sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(tx.Waveform)) && ...
    reference.EndSampleExclusive-reference.StartSample==size(reference.PathGains,1) && ...
    numel(reference.SampleTimes_s)==size(reference.PathGains,1) && ...
    all(abs(diff(reference.SampleTimes_s)*reference.SampleRateHz-1)<1e-6), ...
    'sixgr:pdsch:ExecutedScoringCaptureMismatch', ...
    'Channel coefficients must belong to this transmitted waveform and cover every scored sample.');
carrier=rx.Carrier; ofdm=rx.OFDMInfo; op=rx.ReceiverChannelOperator;
K=12*double(carrier.NSizeGrid); L=double(carrier.SymbolsPerSlot);
R=double(reference.NumReceiveAntennas); T=double(reference.NumTransmitAntennas);
layers=double(tx.NumLayers); estimate=rx.EffectiveLayerChannelEstimate;
assert(isa(tx.PrecoderBundle,'sixgr.pdsch.PDSCHPrecoderBundle') && ...
    isequal([size(estimate,1) size(estimate,2) size(estimate,3) size(estimate,4)],[K L R layers]) && ...
    tx.PrecoderBundle.NPhysicalTxAntennas==T && ...
    tx.Carrier.NSlot==carrier.NSlot && tx.Carrier.NSizeGrid==carrier.NSizeGrid && ...
    reference.SampleRateHz==ofdm.SampleRate && ...
    reference.SampleRateHz==ofdm.Nfft*double(carrier.SubcarrierSpacing)*1000 && ...
    op.AppliedTimingCorrection_samples==0 && ...
    op.CaptureOriginCFOCorrection_Hz==0 && op.AlignedOriginCFOCorrection_Hz==0 && ...
    isequal(op.ReceiveCombiningMatrix,eye(R)), ...
    'sixgr:pdsch:UnsupportedExecutedScoringOperator', ...
    'The scorer requires the executed canonical native FFT and matching antenna/layer maps.');
indices=double(rx.ResourcePlan.DataIndices(:))+1;
assert(~isempty(indices) && numel(unique(indices))==numel(indices) && ...
    all(indices>=1 & indices<=K*L & indices==fix(indices)), ...
    'sixgr:pdsch:InvalidExecutedScoringResources','Retain actual scheduled data REs.');
[bins,symbols]=ind2sub([K L],indices);
first=mod(double(carrier.NSlot),double(ofdm.SlotsPerSubframe))*L;
cp=double(ofdm.SymbolLengths(first+(1:max(symbols))))-double(ofdm.Nfft);
physical=sixgr.truth.receivedFFTChannelDiagonal(reference.PathGains, ...
    reference.PathFilters,double(ofdm.Nfft),cp,K, ...
    double(reference.AppliedAlignmentTrimSamples),double(ofdm.CyclicPrefixFraction));
normalization=1;
if reference.NormalizeChannelOutputs, normalization=1/sqrt(R); end
referenceValues=complex(zeros(numel(indices),R,layers));
estimatedValues=referenceValues;
% Each resource uses its actually transmitted PRG and symbol-group matrix.
for k=1:numel(indices)
    W=tx.PrecoderBundle.slice(floor((bins(k)-1)/12),symbols(k)-1);
    H=reshape(physical(bins(k),symbols(k),:,:),R,T)*W*normalization;
    referenceValues(k,:,:)=reshape(H,1,R,layers);
    estimatedValues(k,:,:)=estimate(bins(k),symbols(k),:,:);
end
assert(all(isfinite(referenceValues),'all') && all(isfinite(estimatedValues),'all'), ...
    'sixgr:pdsch:IncompleteExecutedScoringValues','No extrapolated or missing channel values can be scored.');
errorEnergy=sum(abs(estimatedValues-referenceValues).^2,'all');
referenceEnergy=sum(abs(referenceValues).^2,'all');
assert(isfinite(referenceEnergy) && referenceEnergy>0, ...
    'sixgr:pdsch:ZeroExecutedScoringReference','NMSE requires positive reference energy.');
score=struct('NMSE',errorEnergy/referenceEnergy,'NMSE_dB',10*log10(errorEnergy/referenceEnergy), ...
    'Source',"same_executed_fading_FFT_diagonal_and_transmitted_PRG_matrix", ...
    'ReferencePlane',"nominal_linear_effective_layer_channel_at_actual_receiver_FFT", ...
    'Scope',"scheduled_data_RE_all_received_branches_and_transmitted_layers", ...
    'ComparedValues',numel(referenceValues),'ErrorEnergy',errorEnergy, ...
    'ReferenceEnergy',referenceEnergy,'ChannelOutputNormalizationGain',normalization, ...
    'ReceiverEstimatorInput',false,'GainOrPhaseFitted',false,'AdditionalChannelExecutions',0, ...
    'RFImpairmentsIncluded',false,'PrecoderDigest',tx.PrecoderBundle.ImmutableBundleDigest, ...
    'InputWaveformSHA256',reference.InputWaveformSHA256);
end
