classdef PDSCHImpactEvidenceBuilder
    %PDSCHIMPACTEVIDENCEBUILDER Build the 12-finding impact evidence.
    %
    % Every observation is selected from a persisted production PDSCH
    % phase table whose fail-closed verifier has passed. The result is
    % comparative component evidence, not a new waveform-truth campaign.

    methods (Static)
        function [tables, evidence, records] = build( ...
                matrixPath, rulesPath, vectorRoot, baseDir, cfg, ...
                runID, baseVerifierExit)
            matrix = localReadStrings(matrixPath);
            rules = localReadStrings(rulesPath);
            contract = localReadStrings(fullfile(vectorRoot, ...
                "desired_pdsch_impact_csv_contract.csv"));
            localValidate(matrix, rules, cfg);

            records = repmat(localEmptyRecord(), height(matrix), 1);
            sourceCache = struct();
            for index = 1:height(matrix)
                sourceName = string(matrix.SourceCSV(index));
                field = matlab.lang.makeValidName(sourceName);
                if ~isfield(sourceCache, field)
                    sourcePath = fullfile(baseDir, sourceName);
                    if ~isfile(sourcePath)
                        error("sixgr:pdsch:ImpactSourceMissing", ...
                            "Verified production source is missing: %s.", ...
                            sourcePath);
                    end
                    sourceCache.(field) = struct( ...
                        "Table", localReadStrings(sourcePath), ...
                        "Hash", localFileHash(sourcePath));
                end
                source = sourceCache.(field);
                records(index) = localExecute( ...
                    matrix(index, :), source.Table, source.Hash, cfg);
            end

            raw = localRaw(records, contract, runID);
            operating = localOperating(records, contract, runID);
            effects = localEffects(records, contract, runID);
            ruleTable = localRules(records, rules, effects, contract, runID);

            tables = struct();
            tables.pdsch_impact_run_manifest = localManifest( ...
                matrixPath, rulesPath, baseDir, baseVerifierExit, ...
                contract, runID, cfg);
            tables.pdsch_impact_raw_trials = raw;
            tables.pdsch_impact_operating_points = operating;
            tables.pdsch_impact_pairwise_effects = effects;
            tables.pdsch_impact_rule_evaluation = ruleTable;
            tables.pdsch_impact_assignment = localSpecialized( ...
                records, ["F01","F08","F10"], ...
                "pdsch_impact_assignment.csv", contract, runID);
            tables.pdsch_impact_precoding = localSpecialized( ...
                records, ["F02","F05"], ...
                "pdsch_impact_precoding.csv", contract, runID);
            tables.pdsch_impact_dmrs = localSpecialized( ...
                records, ["F03","F04"], ...
                "pdsch_impact_dmrs.csv", contract, runID);
            tables.pdsch_impact_resource_accounting = localSpecialized( ...
                records, "F06", "pdsch_impact_resource_accounting.csv", ...
                contract, runID);
            tables.pdsch_impact_ptrs = localSpecialized( ...
                records, "F07", "pdsch_impact_ptrs.csv", ...
                contract, runID);
            tables.pdsch_impact_modulation = localSpecialized( ...
                records, "F09", "pdsch_impact_modulation.csv", ...
                contract, runID);
            tables.pdsch_impact_layer_codeword = localSpecialized( ...
                records, "F11", "pdsch_impact_layer_codeword.csv", ...
                contract, runID);
            tables.pdsch_impact_independent_oracles = localSpecialized( ...
                records, "F12", ...
                "pdsch_impact_independent_oracles.csv", contract, runID);
            tables.pdsch_impact_finding_coverage = localCoverage( ...
                records, contract, runID);
            tables.pdsch_impact_summary = localSummary( ...
                records, rules, ruleTable, effects, contract, runID);

            hard = upper(string(rules.Severity)) == "HARD";
            hardIDs = string(rules.RuleID(hard));
            hardRows = ruleTable(ismember( ...
                string(ruleTable.RuleID), hardIDs), :);
            evidence = struct( ...
                "ExperimentCount", height(matrix), ...
                "CompletedCount", numel(records), ...
                "FamilyCount", numel(unique(string(matrix.FamilyID))), ...
                "PairCount", numel(unique(string(matrix.PairID))), ...
                "RuleCount", height(rules), ...
                "HardRuleCount", nnz(hard), ...
                "HardRulePassCount", nnz(localTruth(hardRows.Passed)), ...
                "IncompleteCount", 0, ...
                "HardRulesPassed", all(localTruth(hardRows.Passed)), ...
                "ExecutionBackend", string(cfg.evidence.execution_backend), ...
                "ApproximationMode", ...
                    string(cfg.evidence.approximation_mode), ...
                "TruthQualified", false);
        end
    end
end

function localValidate(matrix, rules, cfg)
if height(matrix) ~= 36 || ...
        numel(unique(string(matrix.ExperimentID))) ~= 36
    error("sixgr:pdsch:ImpactMatrixInvalid", ...
        "PDSCH impact matrix must contain 36 unique experiments.");
end
if numel(unique(string(matrix.FamilyID))) ~= 12 || ...
        numel(unique(string(matrix.PairID))) ~= 12 || ...
        numel(unique(string(matrix.FindingID))) ~= 12
    error("sixgr:pdsch:ImpactMatrixInvalid", ...
        "PDSCH impact matrix must cover 12 findings and pairs.");
end
if height(rules) ~= 24 || numel(unique(string(rules.RuleID))) ~= 24
    error("sixgr:pdsch:ImpactRulesInvalid", ...
        "PDSCH impact pack must contain 24 unique rules.");
end
required = [ ...
    "evidence.execution_backend","evidence.approximation_mode", ...
    "evidence.truth_qualified","execution.required_experiments", ...
    "execution.required_families","execution.required_rules", ...
    "execution.require_all_source_rows_pass", ...
    "images.width_pixels","images.height_pixels", ...
    "images.resolution_dpi"];
for path = required
    if isempty(sixgr.util.structGet(cfg, path, []))
        error("sixgr:pdsch:ImpactStudyConfigInvalid", ...
            "StudyConfig requires field %s.", path);
    end
end
if logical(cfg.evidence.truth_qualified)
    error("sixgr:pdsch:ImpactTruthRelabelForbidden", ...
        "Comparative PDSCH evidence cannot claim waveform truth.");
end
mode = lower(string(cfg.evidence.approximation_mode));
if ~contains(mode, "not_waveform_truth")
    error("sixgr:pdsch:ImpactTruthLabelMissing", ...
        "ApproximationMode must explicitly say not_waveform_truth.");
end
end

function record = localExecute(row, source, sourceHash, cfg)
names = string(source.Properties.VariableNames);
for required = ["Status",string(row.SourceKeyColumn),string(row.Metric)]
    if ~ismember(required, names)
        error("sixgr:pdsch:ImpactSourceInvalid", ...
            "Source %s lacks required column %s.", ...
            row.SourceCSV, required);
    end
end
sourcePass = all(upper(strtrim(string(source.Status))) == "PASS");
if logical(cfg.execution.require_all_source_rows_pass) && ~sourcePass
    error("sixgr:pdsch:ImpactSourceFailed", ...
        "Source %s contains non-PASS production rows.", row.SourceCSV);
end
[observed, key, sourceRows] = localObservation( ...
    source, string(row.SourceKeyColumn), string(row.Metric), ...
    string(row.Selection), string(row.Aggregation));
if ~isfinite(observed)
    error("sixgr:pdsch:ImpactObservationInvalid", ...
        "Experiment %s produced a nonfinite observation.", ...
        row.ExperimentID);
end
record = struct( ...
    "ExperimentID", string(row.ExperimentID), ...
    "FamilyID", string(row.FamilyID), ...
    "PairID", string(row.PairID), ...
    "Variant", string(row.Variant), ...
    "FindingID", string(row.FindingID), ...
    "Title", string(row.Title), ...
    "SourceCSV", string(row.SourceCSV), ...
    "SourceRowKey", key, ...
    "SourceCSV_SHA256", sourceHash, ...
    "Metric", string(row.Metric), ...
    "Aggregation", string(row.Aggregation), ...
    "ObservedValue", observed, "SourceRows", sourceRows, ...
    "SourceRowsPass", sourcePass, ...
    "ExecutionBackend", string(cfg.evidence.execution_backend), ...
    "ApproximationMode", string(cfg.evidence.approximation_mode), ...
    "TruthQualified", false, "Status", "PASS");
end

function [observed, key, sourceRows] = localObservation( ...
        source, keyColumn, metric, selection, aggregation)
groups = unique(string(source.(char(keyColumn))), "stable");
groups = groups(strlength(strtrim(groups)) > 0);
values = nan(numel(groups), 1);
counts = zeros(numel(groups), 1);
for index = 1:numel(groups)
    rows = source(string(source.(char(keyColumn))) == groups(index), :);
    counts(index) = height(rows);
    values(index) = localAggregate(rows.(char(metric)), aggregation);
end
finite = isfinite(values);
groups = groups(finite);
counts = counts(finite);
values = values(finite);
if isempty(values)
    error("sixgr:pdsch:ImpactObservationInvalid", ...
        "No finite value exists for metric %s.", metric);
end
[values, order] = sort(values);
groups = groups(order);
counts = counts(order);
switch lower(selection)
    case "low"
        selected = 1;
    case "mid"
        selected = ceil(numel(values) / 2);
    case "high"
        selected = numel(values);
    otherwise
        error("sixgr:pdsch:ImpactSelectionInvalid", ...
            "Unknown selection %s.", selection);
end
observed = values(selected);
key = groups(selected);
sourceRows = counts(selected);
end

function value = localAggregate(input, aggregation)
switch lower(aggregation)
    case "truth_fraction"
        value = mean(double(localTruth(input)));
    case "numeric_mean"
        numeric = str2double(string(input));
        numeric = numeric(isfinite(numeric));
        if isempty(numeric)
            value = NaN;
        else
            value = mean(numeric);
        end
    otherwise
        error("sixgr:pdsch:ImpactAggregationInvalid", ...
            "Unknown aggregation %s.", aggregation);
end
end

