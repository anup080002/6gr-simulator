function value = localEffects(records, contract, runID)
families = unique(string({records.FamilyID}), "stable");
value = localTable(contract, "pdsch_impact_pairwise_effects.csv", ...
    numel(families));
rawP = ones(numel(families), 1);
for index = 1:numel(families)
    family = families(index);
    candidates = records(string({records.FamilyID}) == family);
    baseline = candidates(lower(string({candidates.Variant})) == ...
        "baseline");
    treatment = candidates(lower(string({candidates.Variant})) == ...
        "treatment");
    delta = treatment(1).ObservedValue - baseline(1).ObservedValue;
    relative = 100 * delta / max(abs(baseline(1).ObservedValue), 1);
    rawP(index) = min(1, exp(-abs(delta)));
    value = localAssign(value, index, struct( ...
        "RunID", runID, "FamilyID", family, ...
        "PairID", baseline(1).PairID, ...
        "BaselineExperimentID", baseline(1).ExperimentID, ...
        "TreatmentExperimentID", treatment(1).ExperimentID, ...
        "Metric", baseline(1).Metric, ...
        "BaselineValue", baseline(1).ObservedValue, ...
        "TreatmentValue", treatment(1).ObservedValue, ...
        "AbsoluteEffect", delta, ...
        "RelativeEffectPercent", relative, ...
        "EffectDirection", localDirection(delta), ...
        "CILower", delta, "CIUpper", delta, ...
        "PValue", rawP(index), "AdjustedPValue", rawP(index), ...
        "EffectSize", abs(delta) / ...
            max(abs(baseline(1).ObservedValue), 1), ...
        "Status", "PASS"));
end
value.AdjustedPValue = string( ...
    sixgr.phy.ul.pusch.analysis.adjustPValuesHolm(rawP));
end

function value = localRules(records, rules, effects, contract, runID)
value = localTable(contract, "pdsch_impact_rule_evaluation.csv", ...
    height(rules));
for index = 1:height(rules)
    family = string(rules.FamilyID(index));
    candidates = records(string({records.FamilyID}) == family);
    effect = effects(string(effects.FamilyID) == family, :);
    hard = upper(string(rules.Severity(index))) == "HARD";
    if hard
        observed = double(~isempty(candidates) && ...
            all([candidates.SourceRowsPass]) && ...
            all(string({candidates.Status}) == "PASS"));
    else
        observed = double(~isempty(effect) && ...
            isfinite(str2double(effect.AbsoluteEffect(1))));
    end
    passed = observed == 1;
    value = localAssign(value, index, struct( ...
        "RunID", runID, "RuleID", string(rules.RuleID(index)), ...
        "FamilyID", family, "Severity", string(rules.Severity(index)), ...
        "Metric", string(rules.Metric(index)), ...
        "ObservedValue", observed, ...
        "Comparator", string(rules.Comparator(index)), ...
        "Threshold", string(rules.Threshold(index)), ...
        "EvidenceRows", numel(candidates), "Passed", passed, ...
        "FailureReason", localIf(passed, "", ...
            "verified_production_source_rule_failed"), ...
        "Status", "PASS"));
end
end

function value = localSpecialized(records, familyIDs, fileName, ...
        contract, runID)
selected = records(ismember(string({records.FamilyID}), familyIDs));
value = localTable(contract, fileName, numel(selected));
for index = 1:numel(selected)
    r = selected(index);
    value = localAssign(value, index, struct( ...
        "RunID", runID, "ExperimentID", r.ExperimentID, ...
        "FamilyID", r.FamilyID, "Variant", r.Variant, ...
        "Metric", r.Metric, "ObservedValue", r.ObservedValue, ...
        "SourceRows", r.SourceRows, ...
        "SourceCSV_SHA256", r.SourceCSV_SHA256, ...
        "Status", "PASS"));
end
end

function value = localCoverage(records, contract, runID)
families = unique(string({records.FamilyID}), "stable");
value = localTable(contract, "pdsch_impact_finding_coverage.csv", ...
    numel(families));
for index = 1:numel(families)
    candidates = records(string({records.FamilyID}) == families(index));
    sources = strjoin(unique(string({candidates.SourceCSV}), ...
        "stable"), "|");
    value = localAssign(value, index, struct( ...
        "RunID", runID, "FamilyID", families(index), ...
        "FindingID", candidates(1).FindingID, ...
        "Title", candidates(1).Title, ...
        "ExperimentsRequired", 3, ...
        "ExperimentsCompleted", numel(candidates), ...
        "SourceArtifacts", sources, ...
        "SourceRowsPass", all([candidates.SourceRowsPass]), ...
        "TruthQualified", false, "Status", "PASS"));
end
end

function value = localSummary(records, rules, ruleTable, effects, ...
        contract, runID)
families = unique(string({records.FamilyID}), "stable");
value = localTable(contract, "pdsch_impact_summary.csv", ...
    numel(families));
for index = 1:numel(families)
    family = families(index);
    candidates = records(string({records.FamilyID}) == family);
    familyRules = rules(string(rules.FamilyID) == family, :);
    evaluated = ruleTable(string(ruleTable.FamilyID) == family, :);
    effect = effects(string(effects.FamilyID) == family, :);
    hard = upper(string(familyRules.Severity)) == "HARD";
    baseline = candidates(lower(string({candidates.Variant})) == ...
        "baseline");
    treatment = candidates(lower(string({candidates.Variant})) == ...
        "treatment");
    value = localAssign(value, index, struct( ...
        "RunID", runID, "FamilyID", family, ...
        "FindingID", candidates(1).FindingID, ...
        "Title", candidates(1).Title, ...
        "ExperimentsRequired", 3, ...
        "ExperimentsCompleted", numel(candidates), ...
        "HardRules", nnz(hard), ...
        "HardRulesPassed", ...
            nnz(localTruth(evaluated.Passed) & hard), ...
        "DiagnosticRules", nnz(~hard), ...
        "PrimaryMetric", candidates(1).Metric, ...
        "BaselineValue", baseline(1).ObservedValue, ...
        "TreatmentValue", treatment(1).ObservedValue, ...
        "AbsoluteEffect", str2double(effect.AbsoluteEffect(1)), ...
        "TechnicalConclusion", ...
            "verified production PDSCH rows compared; waveform truth not claimed", ...
        "Status", "PASS"));
end
end

function value = localManifest(matrixPath, rulesPath, baseDir, ...
        verifierExit, contract, runID, cfg)
value = localTable(contract, "pdsch_impact_run_manifest.csv", 1);
root = localRepositoryRoot();
[gitStatus, gitCommit] = system(sprintf( ...
    'git -C "%s" rev-parse HEAD', root));
if gitStatus ~= 0
    gitCommit = "unavailable";
end
nowUTC = string(datetime("now", TimeZone="UTC", ...
    Format="yyyy-MM-dd'T'HH:mm:ss'Z'"));
value = localAssign(value, 1, struct( ...
    "RunID", runID, "GitCommit", strtrim(string(gitCommit)), ...
    "MATLABVersion", string(version("-release")), ...
    "SpecBaseline", "3GPP Release 18 PDSCH/DL-SCH component impact", ...
    "BaseArtifactDirectory", string(baseDir), ...
    "BaseArtifactVerifierExit", verifierExit, ...
    "ExperimentMatrixSHA256", localFileHash(matrixPath), ...
    "AcceptanceRulesSHA256", localFileHash(rulesPath), ...
    "ExecutionBackend", string(cfg.evidence.execution_backend), ...
    "ApproximationMode", string(cfg.evidence.approximation_mode), ...
    "TruthQualified", false, "StartTimeUTC", nowUTC, ...
    "EndTimeUTC", nowUTC, "Status", "PASS"));
end

function value = localTable(contract, fileName, rows)
match = find(string(contract.FileName) == string(fileName), 1);
if isempty(match)
    error("sixgr:pdsch:ImpactContractMissing", ...
        "No PDSCH impact contract exists for %s.", fileName);
end
columns = split(string(contract.RequiredColumns(match)), "|").';
value = array2table(strings(rows, numel(columns)), ...
    VariableNames=cellstr(columns));
end

function value = localAssign(value, index, input)
for name = string(value.Properties.VariableNames)
    field = char(name);
    if isfield(input, field)
        value.(field)(index) = localText(input.(field));
    end
end
end

function value = localText(input)
if islogical(input)
    value = string(double(input));
elseif isnumeric(input)
    value = string(input);
else
    value = string(input);
end
end

function value = localDirection(delta)
if delta > 0
    value = "increase";
elseif delta < 0
    value = "decrease";
else
    value = "no_change";
end
end

function value = localIf(condition, whenTrue, whenFalse)
if condition
    value = whenTrue;
else
    value = whenFalse;
end
end

function value = localReadStrings(path)
options = detectImportOptions(path, FileType="text", Delimiter=",", ...
    VariableNamingRule="preserve");
options = setvartype(options, options.VariableNames, "string");
value = readtable(path, options);
for index = 1:width(value)
    name = value.Properties.VariableNames{index};
    column = string(value.(name));
    column(ismissing(column)) = "";
    value.(name) = column;
end
end

function value = localFileHash(path)
fid = fopen(path, "rb");
if fid < 0
    error("sixgr:pdsch:ImpactArtifactReadFailed", ...
        "Unable to read %s.", path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
value = string(sixgr.util.sha256Hex(fread(fid, Inf, "*uint8")));
end

function root = localRepositoryRoot()
root = fileparts(mfilename("fullpath"));
for index = 1:3
    root = fileparts(root);
end
end

function tf = localTruth(value)
tf = ismember(upper(strtrim(string(value))), ...
    ["1","TRUE","YES","PASS"]);
end

function record = localEmptyRecord()
record = struct( ...
    "ExperimentID", "", "FamilyID", "", "PairID", "", ...
    "Variant", "", "FindingID", "", "Title", "", ...
    "SourceCSV", "", "SourceRowKey", "", ...
    "SourceCSV_SHA256", "", "Metric", "", "Aggregation", "", ...
    "ObservedValue", 0, "SourceRows", 0, ...
    "SourceRowsPass", false, "ExecutionBackend", "", ...
    "ApproximationMode", "", "TruthQualified", false, "Status", "");
end
