value = localTable(contract, "pdsch_impact_raw_trials.csv", ...
    numel(records));
for index = 1:numel(records)
    r = records(index);
    value = localAssign(value, index, struct( ...
        "RunID", runID, "ExperimentID", r.ExperimentID, ...
        "FamilyID", r.FamilyID, "PairID", r.PairID, ...
        "Variant", r.Variant, "FindingID", r.FindingID, ...
        "Title", r.Title, "SourceCSV", r.SourceCSV, ...
        "SourceRowKey", r.SourceRowKey, ...
        "SourceCSV_SHA256", r.SourceCSV_SHA256, ...
        "Metric", r.Metric, "Aggregation", r.Aggregation, ...
        "ObservedValue", r.ObservedValue, ...
        "SourceRows", r.SourceRows, ...
        "SourceRowsPass", r.SourceRowsPass, ...
        "ExecutionBackend", r.ExecutionBackend, ...
        "ApproximationMode", r.ApproximationMode, ...
        "TruthQualified", false, "Status", "PASS"));
end
end

