classdef PDSCHHARQContext
    %PDSCHHARQContext Immutable codeword-specific PDSCH HARQ state.

    properties (SetAccess = immutable)
        Data (1,1) struct
        KeyDigest (1,1) string
    end

    methods
        function obj = PDSCHHARQContext(data)
            arguments
                data (1,1) struct
            end
            required = [ ...
                "UEId","ServingCellId","SchedulingCellId","CCId","BWPId", ...
                "HARQProcessId","CodewordIndex","ConfigurationEpoch", ...
                "NDI","TBIdentityDigest","TBS","CodingPlanDigest", ...
                "BaseGraph","LiftingSize","CodeBlockLayout", ...
                "FillerPositions","Ncb","Nref","RVHistory", ...
                "CircularBufferLLR","ValidPositionMask","TransmissionCount", ...
                "LastDecodeOutcome"];
            missing = required(~isfield(data, required));
            if ~isempty(missing)
                error("sixgr:pdsch:IncompleteHARQContext", ...
                    "PDSCH HARQ context is missing: %s.", ...
                    strjoin(cellstr(missing), ", "));
            end
            obj.Data = orderfields(data);
            obj.KeyDigest = sixgr.pdsch.PDSCHHARQContext.digestKey(data);
        end

        function value = toStruct(obj)
            value = obj.Data;
        end
    end

    methods (Static)
        function digest = digestKey(data)
            key = struct( ...
                "UEId", double(data.UEId), ...
                "ServingCellId", double(data.ServingCellId), ...
                "SchedulingCellId", double(data.SchedulingCellId), ...
                "CCId", double(data.CCId), ...
                "BWPId", double(data.BWPId), ...
                "HARQProcessId", double(data.HARQProcessId), ...
                "CodewordIndex", double(data.CodewordIndex), ...
                "ConfigurationEpoch", double(data.ConfigurationEpoch));
            bytes = uint8(unicode2native(jsonencode(orderfields(key)), "UTF-8"));
            digest = string(sixgr.util.sha256Hex(bytes));
        end
    end
end
