classdef CommonPDSCHQCLReference
    % Common-procedure RS association is not a MAC-activated TCI state.
    % TS 38.214 5.1: SI and Msg4 use the associated SS/PBCH block;
    % the currently implemented SSB-associated CBRA path uses it for RAR.
    methods (Static)
        function reference = create(procedure, ssbIndex, servingCell, authority)
            validateattributes(ssbIndex,{'numeric'}, ...
                {'scalar','real','finite','integer','nonnegative'});
            validateattributes(servingCell,{'numeric'}, ...
                {'scalar','real','finite','integer','nonnegative'});
            procedure=string(procedure); authority=string(authority);
            if ~isscalar(procedure) || ~any(procedure== ...
                    ["sib1","msg2_rar","msg4_contention_resolution"]) || ...
                    ~isscalar(authority) || ismissing(authority) || strlength(strtrim(authority))==0
                error('sixgr:pdsch:MissingCommonQCLReference', ...
                    'A supported common procedure and explicit reference authority are required.');
            end
            reference=struct('Procedure',procedure,'ServingCellId',double(servingCell), ...
                'SourceReferenceSignal',"SSB",'SourceReferenceSignalId',double(ssbIndex), ...
                'SourceAuthority',authority,'QCLTypes',"A|D", ...
                'SpatialParametersApplicability',"when_applicable", ...
                'Assumptions',"TS_38_214_5_1_common_procedure_RS_association", ...
                'BindingKind',"common_procedure_reference", ...
                'TCIActivationApplicable',false, ...
                'ReceiverParameterReuseStatus',"not_evaluated_by_reference_binding");
        end

        function reference = fromRA(cfg, procedure, servingCell)
            index=sixgr.util.structGet(cfg,'random_access.associated_ssb_index',NaN);
            selection=sixgr.phy.ia.SSBBurstPlan.selectedPrecoderFromConfig(cfg,index);
            [~,~,association]=sixgr.phy.ra.resolveAssociatedSSBProjection( ...
                cfg,selection.NumTransmitAntennas);
            reference=sixgr.pdsch.CommonPDSCHQCLReference.create( ...
                procedure,index,servingCell,association.SelectionSource);
            reference.TransmitAssociation=association;
        end

        function reference = validate(reference, assignment)
            required=["Procedure","ServingCellId","SourceReferenceSignal", ...
                "SourceReferenceSignalId","SourceAuthority","QCLTypes", ...
                "SpatialParametersApplicability","Assumptions","BindingKind", ...
                "TCIActivationApplicable","ReceiverParameterReuseStatus"];
            if ~isstruct(reference) || ~isscalar(reference) || any(~isfield(reference,required))
                error('sixgr:pdsch:MissingCommonQCLReference', ...
                    'Common PDSCH requires an explicit associated reference, not a fabricated activated TCI.');
            end
            expected=sixgr.pdsch.CommonPDSCHQCLReference.create( ...
                reference.Procedure,reference.SourceReferenceSignalId, ...
                reference.ServingCellId,reference.SourceAuthority);
            for field=required
                if ~isequal(reference.(field),expected.(field))
                    error('sixgr:pdsch:InvalidCommonQCLReference','Invalid common reference field %s.',field);
                end
            end
            procedures=["sib1","msg2_rar","msg4_contention_resolution"];
            rntis=["SI-RNTI","RA-RNTI","TC-RNTI"];
            if string(assignment.Profile)~="ra_si_strict" || ...
                    reference.ServingCellId~=assignment.ServingCellId || ...
                    rntis(procedures==reference.Procedure)~=string(assignment.RNTIType)
                error('sixgr:pdsch:CommonQCLAssignmentMismatch', ...
                    'Common reference procedure/cell does not match the PDSCH assignment.');
            end
        end
    end
end
