                "PRBSet", data.PRBSetCarrierRelative, ...
                "Symbols", data.SymbolAllocation, "HARQProcessId", data.HARQProcessId);
            bytes = uint8(unicode2native(jsonencode(orderfields(payload)), "UTF-8"));
            hash = string(sixgr.util.sha256Hex(bytes));
            id = "PDSCH-" + upper(extractBefore(hash, 17));
        end

