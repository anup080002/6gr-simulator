            sixgr.pdsch.PDSCHAssignmentFactory.requirePresentLogical( ...
                decodedDCI, "DCIEnabled1024QAM");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                harqState, "Consistent", "HARQContextMismatch");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                decodedDCI, "FieldsInRange", "DCIFieldOutOfRange");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                ueContext, "TCIStateActive", "TCIStateNotActivated");
            sixgr.pdsch.PDSCHAssignmentFactory.requireFrameAndHARQState( ...
                frameState, harqState);

            rntiType = upper(strtrim(string(decodedDCI.RNTIType)));
            format = strrep(string(decodedDCI.Format), "_", "_");
            if ~sixgr.pdsch.PDSCHAssignmentFactory.validDCIRNTIProcedure(format, rntiType)
                error("sixgr:pdsch:InvalidDCIRNTIProcedure", ...
                    "DCI format '%s' is not valid for RNTI type '%s'.", format, rntiType);
            end

            if any(rntiType == ["SI-RNTI","P-RNTI","RA-RNTI","TC-RNTI"])
                profile = "ra_si_strict";
                source = "decoded_dci+procedure_context";
            else
                profile = "connected_strict";
                source = "decoded_dci+ue_context";
            end
            data = sixgr.pdsch.PDSCHAssignmentFactory.baseData(profile, source);
            data = sixgr.pdsch.PDSCHAssignmentFactory.populateCommon( ...
                data, decodedDCI, ueContext, frameState, harqState);
            data.DecodedDCIId = string(decodedDCI.Id);
            data.ScheduledDCIId = "";
