            payload = struct( ...
                "Profile", data.Profile, "UEId", data.UEId, ...
                "ServingCellId", data.ServingCellId, "CCId", data.CCId, ...
                "BWPId", data.BWPId, "ConfigurationEpoch", data.ConfigurationEpoch, ...
