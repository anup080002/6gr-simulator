            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                decodedDCI, "CRCPass", "DCICRCFailed");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                decodedDCI, "RNTIMatch", "DCIRNTIMismatch");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                ueContext, "ActiveBWPContextPresent", "MissingActiveBWPContext");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                ueContext, "EpochCurrent", "StaleUEConfigurationEpoch");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                ueContext, "ServingCellActive", "InactiveServingCell");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                frameState, "ResourceAvailable", "ScheduledResourceUnavailable");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                ueContext, "MCSContextSupported", "UnsupportedMCSContext");
            sixgr.pdsch.PDSCHAssignmentFactory.requirePresentLogical( ...
                ueContext, "UECapability1024QAM");
            sixgr.pdsch.PDSCHAssignmentFactory.requirePresentLogical( ...
                ueContext, "RRCEnabled1024QAM");
            sixgr.pdsch.PDSCHAssignmentFactory.requirePresentLogical( ...
                ueContext, "DeploymentAllows1024QAM");
            sixgr.pdsch.PDSCHAssignmentFactory.requirePresentText( ...
                ueContext, "FrequencyRange");
            sixgr.pdsch.PDSCHAssignmentFactory.requirePresentText( ...
                ueContext, "OperatingBand");
            sixgr.pdsch.PDSCHAssignmentFactory.requirePresentText( ...
