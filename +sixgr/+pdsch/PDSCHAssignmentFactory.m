                end
            end
            data.PDSCHAbsoluteSlot = double(frameState.AbsoluteSlot);
            data.PDCCHAbsoluteSlot = double(request.PDCCHAbsoluteSlot);
            data.K0 = double(request.K0);
            data.DecodedDCIId = string(request.DecodedDCIId);
