            data.DCICRCPass = true;
            data.DCIRNTIMatch = true;
            data.DecodedRNTI = double(decodedDCI.DecodedRNTI);
            data.PDCCHAbsoluteSlot = double(decodedDCI.PDCCHAbsoluteSlot);
            data.AssignmentId = sixgr.pdsch.PDSCHAssignmentFactory.assignmentId(data);
            assignment = sixgr.pdsch.PDSCHSchedulingAssignment(data);
        end

        function assignment = fromScheduledDCI(scheduledDCI, ueContext, frameState, harqState)
            %FROMSCHEDULEDDCI Build TX ownership from the actual scheduled DCI.
            % No receiver CRC or RNTI-match claim is made on this path.
            scheduledDCI = sixgr.pdsch.PDSCHAssignmentFactory.asStruct( ...
                scheduledDCI, "sixgr:pdsch:MissingScheduledDCI");
            ueContext = sixgr.pdsch.PDSCHAssignmentFactory.asStruct( ...
                ueContext, "sixgr:pdsch:MissingUEContext");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                scheduledDCI, "Present", "MissingScheduledDCI");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                scheduledDCI, "FieldsInRange", "DCIFieldOutOfRange");
            for fieldName = ["ActiveBWPContextPresent","EpochCurrent", ...
                    "ServingCellActive","MCSContextSupported","TCIStateActive"]
                sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                    ueContext, fieldName, "Invalid" + fieldName);
            end
            for fieldName = ["UECapability1024QAM","RRCEnabled1024QAM", ...
                    "DeploymentAllows1024QAM","FrequencyRangeAllows1024QAM", ...
                    "BandAllows1024QAM"]
                sixgr.pdsch.PDSCHAssignmentFactory.requirePresentLogical( ...
                    ueContext, fieldName);
            end
            for fieldName = ["FrequencyRange","OperatingBand","DeploymentClass"]
                sixgr.pdsch.PDSCHAssignmentFactory.requirePresentText( ...
                    ueContext, fieldName);
            end
            sixgr.pdsch.PDSCHAssignmentFactory.requirePresentLogical( ...
                scheduledDCI, "DCIEnabled1024QAM");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                frameState, "ResourceAvailable", "ScheduledResourceUnavailable");
            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
                harqState, "Consistent", "HARQContextMismatch");
            sixgr.pdsch.PDSCHAssignmentFactory.requireFrameAndHARQState( ...
                frameState, harqState);

            rntiType = upper(strtrim(string(scheduledDCI.RNTIType)));
            format = string(scheduledDCI.Format);
            if ~any(rntiType == ["SI-RNTI","P-RNTI","RA-RNTI","TC-RNTI"]) || ...
                    ~sixgr.pdsch.PDSCHAssignmentFactory.validDCIRNTIProcedure(format, rntiType)
                error("sixgr:pdsch:InvalidDCIRNTIProcedure", ...
                    "Scheduled common-procedure DCI '%s' is invalid for '%s'.", ...
                    format, rntiType);
            end
            data = sixgr.pdsch.PDSCHAssignmentFactory.baseData( ...
                "ra_si_strict", "scheduled_dci+procedure_context");
            data = sixgr.pdsch.PDSCHAssignmentFactory.populateCommon( ...
                data, scheduledDCI, ueContext, frameState, harqState);
            data.ScheduledDCIId = string(scheduledDCI.Id);
            data.DecodedDCIId = "";
            data.ControlAuthority = "transmitter_scheduled_dci";
            data.DCIFormat = string(scheduledDCI.Format);
            data.DCICRCPass = false;
            data.DCIRNTIMatch = false;
            data.DecodedRNTI = NaN;
            data.PDCCHAbsoluteSlot = double(scheduledDCI.PDCCHAbsoluteSlot);
            data.AssignmentId = sixgr.pdsch.PDSCHAssignmentFactory.assignmentId(data);
            assignment = sixgr.pdsch.PDSCHSchedulingAssignment(data);
        end

