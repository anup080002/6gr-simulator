            arguments
                decodedDCI
                ueContext
                frameState (1,1) struct
                harqState (1,1) struct
            end

            decodedDCI = sixgr.pdsch.PDSCHAssignmentFactory.asStruct( ...
                decodedDCI, "sixgr:pdsch:MissingDecodedDCI");
            ueContext = sixgr.pdsch.PDSCHAssignmentFactory.asStruct( ...
                ueContext, "sixgr:pdsch:MissingUEContext");

            sixgr.pdsch.PDSCHAssignmentFactory.requireLogical( ...
