    methods (Static, Access = private)
        function requireFrameAndHARQState(frameState, harqState)
            if ~isfield(frameState, "AbsoluteSlot") ...
                    || ~(isnumeric(frameState.AbsoluteSlot) ...
                    && isscalar(frameState.AbsoluteSlot) ...
                    && isfinite(frameState.AbsoluteSlot) ...
                    && frameState.AbsoluteSlot == fix(frameState.AbsoluteSlot) ...
                    && frameState.AbsoluteSlot >= 0)
                error("sixgr:pdsch:IncompleteFrameState", ...
                    ["Decoded/SPS assignment requires an explicit " ...
                    "nonnegative-integer AbsoluteSlot."]);
            end
            if ~isfield(harqState, "ProcessId") ...
                    || ~(isnumeric(harqState.ProcessId) ...
                    && isscalar(harqState.ProcessId) ...
                    && isfinite(harqState.ProcessId) ...
                    && harqState.ProcessId == fix(harqState.ProcessId) ...
                    && harqState.ProcessId >= 0)
                error("sixgr:pdsch:IncompleteHARQState", ...
                    ["PDSCH assignment requires an explicit " ...
                    "nonnegative-integer HARQ ProcessId."]);
            end
        end

        function requireLogical(value, fieldName, token)
            if ~isfield(value, fieldName) ...
                    || ~(islogical(value.(fieldName)) ...
                    && isscalar(value.(fieldName))) ...
                    || ~value.(fieldName)
                error("sixgr:pdsch:" + token, ...
                    "PDSCH assignment validation failed: %s.", token);
            end
        end

        function requirePresentLogical(value, fieldName)
            if ~isfield(value, fieldName) || ...
                    ~(islogical(value.(fieldName)) && isscalar(value.(fieldName)))
                error("sixgr:pdsch:Incomplete1024QAMCapabilityContext", ...
                    "%s must be present as an explicit logical scalar.", fieldName);
            end
        end

        function requirePresentText(value, fieldName)
            if ~isfield(value, fieldName) ...
                    || ~(ischar(value.(fieldName)) ...
                    || (isstring(value.(fieldName)) ...
                    && isscalar(value.(fieldName)))) ...
                    || strlength(strtrim(string(value.(fieldName)))) == 0
                error("sixgr:pdsch:IncompleteDeploymentContext", ...
                    "%s must be present as an explicit nonempty token.", ...
                    fieldName);
            end
        end

        function tf = validDCIRNTIProcedure(format, rntiType)
            format = upper(strtrim(string(format)));
            rntiType = upper(strtrim(string(rntiType)));
            if rntiType == "C-RNTI"
                tf = any(format == ["1_0","1_1","1_2","1_3"]);
            elseif any(rntiType == ["CS-RNTI","MCS-C-RNTI"])
                tf = any(format == ["1_0","1_1","1_2"]);
            elseif any(rntiType == ["SI-RNTI","P-RNTI","RA-RNTI","TC-RNTI"])
                tf = format == "1_0";
            else
                tf = false;
            end
        end

