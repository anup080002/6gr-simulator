        function assignment = forCalibration(request, frameState)
            arguments
                request (1,1) struct
                frameState (1,1) struct
            end

            required = [ ...
                "UEId","RNTI","RNTIType","ServingCellId","SchedulingCellId", ...
                "CCId","BWPId","ConfigurationEpoch","PRBSetBWPRelative", ...
                "PRBSetCarrierRelative","SymbolAllocation","MappingType", ...
                "MCSTablePerCodeword","MCSIndexPerCodeword", ...
                "ModulationPerCodeword","QmPerCodeword", ...
                "TargetCodeRatePerCodeword","TBScalingPerCodeword","XOverhead", ...
                "NumLayers","NumCodewords","LayerCountPerCodeword", ...
                "DMRSPortSet","NDIPerCodeword","RVPerCodeword","HARQProcessId"];
            required = [required, ...
                "UECapability1024QAM","RRCEnabled1024QAM", ...
                "DCIEnabled1024QAM","DeploymentAllows1024QAM", ...
                "FrequencyRange","OperatingBand","DeploymentClass", ...
                "FrequencyRangeAllows1024QAM", ...
                "BandAllows1024QAM"];
            missing = required(~isfield(request, required));
            if ~isempty(missing)
                error("sixgr:pdsch:IncompleteCalibrationAssignment", ...
                    "Explicit PDSCH calibration request is missing: %s.", ...
                    strjoin(cellstr(missing), ", "));
            end
            if ~isfield(frameState, "ResourceAvailable") || ...
                    ~logical(frameState.ResourceAvailable)
                error("sixgr:pdsch:ScheduledResourceUnavailable", ...
                    "Calibration assignment resources are unavailable.");
            end
            if ~isfield(frameState, "AbsoluteSlot") ...
                    || ~(isnumeric(frameState.AbsoluteSlot) ...
                    && isscalar(frameState.AbsoluteSlot) ...
                    && isfinite(frameState.AbsoluteSlot) ...
                    && frameState.AbsoluteSlot == fix(frameState.AbsoluteSlot) ...
                    && frameState.AbsoluteSlot >= 0)
                error("sixgr:pdsch:IncompleteCalibrationFrameState", ...
                    ["Calibration frame state requires an explicit " ...
                    "nonnegative-integer AbsoluteSlot."]);
            end

            data = sixgr.pdsch.PDSCHAssignmentFactory.baseData( ...
                "phy_calibration", "calibration_assignment");
            names = fieldnames(request);
            for idx = 1:numel(names)
                if isfield(data, names{idx})
                    data.(names{idx}) = request.(names{idx});
                end
            end
            data.PDSCHAbsoluteSlot = double(frameState.AbsoluteSlot);
            data.PDCCHAbsoluteSlot = NaN;
            data.DecodedDCIId = "";
            data.DCIFormat = string(sixgr.util.structGet( ...
                request, "DCIFormat", "not_applicable_calibration"));
            data.DCICRCPass = false;
            data.DCIRNTIMatch = false;
            data.AssignmentId = sixgr.pdsch.PDSCHAssignmentFactory.assignmentId(data);
            assignment = sixgr.pdsch.PDSCHSchedulingAssignment(data);
        end

