classdef PDSCHReferenceSignalGenerator
    %PDSCHREFERENCESIGNALGENERATOR Canonical PDSCH DM-RS/PT-RS boundary.
    %
    % Planning may call resolveIndices.  Only generate materializes
    % reference symbols, and it independently validates the generated
    % indices/sequences before returning them to the transmitter.

    methods (Static)
        function resolved = resolveIndices(assignment,carrier,config)
            localRequireInputs(assignment,carrier,config);
            config.validateForExecution();
            assignment.validateForExecution();
            reference = config.toStruct();
            pdsch = sixgr.pdsch.PDSCHConfigMaterializer. ...
                fromAssignment(assignment,reference);
            dmrsValidation = localValidateDMRS(assignment,reference);
            ports = double(assignment.get("DMRSPortSet"));
            rankValue = double(assignment.get("NumLayers"));
            [dmrsCells,dmrsSubscripts] = localDMRSIndices( ...
                carrier,pdsch,ports);
            oracleDMRS = sixgr.pdsch.oracle.DMRSIndexSpec.resolve(struct( ...
                "GridNumPRB",double(carrier.NSizeGrid), ...
                "PRBSet",double(assignment.get( ...
                    "PRBSetCarrierRelative")), ...
                "DMRSSymbols",dmrsValidation.SymbolPositions, ...
                "DMRSConfigurationType", ...
                    double(reference.DMRSConfigurationType), ...
                "DMRSPortSet",ports));
            dmrsMismatch = localCellIndexMismatch( ...
                dmrsCells,oracleDMRS.IndicesPerPort);
            if dmrsMismatch ~= 0
                error("sixgr:pdsch:DMRSIndependentIndexMismatch", ...
                    "Production DM-RS indices differ from the independent " + ...
                    "oracle at %d position(s).",dmrsMismatch);
            end

            ptrsCells = repmat({zeros(1,0)},1,rankValue);
            ptrsSubscripts = zeros(0,3);
            ptrsOracle = struct("Indices0Based",zeros(0,1), ...
                "IndexBase","zero_based");
            ptrsMismatch = 0;
            if logical(reference.EnablePTRS)
                ptrsPortSet = double(assignment.get("PTRSPortSet"));
                if numel(ptrsPortSet) ~= 1 ...
                        || ~ismember(ptrsPortSet,ports)
                    error("sixgr:pdsch:InvalidPTRSPortAssociation", ...
                        "Enabled PT-RS requires one port associated with DM-RS.");
                end
                ptrsRequest = localPTRSIndexRequest( ...
                    assignment,carrier,reference, ...
                    dmrsValidation.SymbolPositions);
                resolvedPTRS = sixgr.pdsch.PDSCHPTRSResolver. ...
                    resolveIndices(ptrsRequest);
                ptrsOracle = sixgr.pdsch.oracle.PTRSIndexSpec. ...
                    resolve(ptrsRequest);
                ptrsMismatch = localIndexMismatch( ...
                    resolvedPTRS.Indices0Based, ...
                    ptrsOracle.Indices0Based);
                if ptrsMismatch ~= 0
                    error("sixgr:pdsch:PTRSIndependentIndexMismatch", ...
                        "Production PT-RS indices differ from the independent " + ...
                        "oracle at %d position(s).",ptrsMismatch);
                end
                layer = find(ports == ptrsPortSet,1);
                ptrsCells{layer} = ...
                    double(resolvedPTRS.Indices0Based(:).');
                K = double(carrier.NSizeGrid)*12;
                ptrsSubscripts = [ ...
                    mod(resolvedPTRS.Indices0Based(:),K), ...
                    floor(resolvedPTRS.Indices0Based(:)/K), ...
                    repmat(ptrsPortSet, ...
                        numel(resolvedPTRS.Indices0Based),1)];
            elseif ~isempty(assignment.get("PTRSPortSet"))
                error("sixgr:pdsch:PTRSPresenceAssignmentMismatch", ...
                    "Disabled PT-RS cannot retain an assigned PT-RS port.");
            end

            resolved = struct( ...
                "ContractVersion","PDSCHReferenceIndices/v1", ...
                "ConfigurationDigest",config.ConfigurationDigest, ...
                "DMRSIndicesPerPort",{dmrsCells}, ...
                "PTRSIndicesPerPort",{ptrsCells}, ...
                "DMRSLogicalPortSet",ports, ...
                "PTRSLogicalPortSet",ports, ...
                "DMRSSubscripts0Based",double(dmrsSubscripts), ...
                "PTRSSubscripts0Based",double(ptrsSubscripts), ...
                "DMRSSymbolPositions", ...
                    double(dmrsValidation.SymbolPositions), ...
                "DMRSIndexMismatchCount",double(dmrsMismatch), ...
                "PTRSIndexMismatchCount",double(ptrsMismatch), ...
                "DMRSOracle",oracleDMRS, ...
                "PTRSOracle",ptrsOracle, ...
                "MaterializedPDSCH",pdsch, ...
                "IndexBase","zero_based", ...
                "Source","explicit_config+toolbox_kernel+independent_oracle");
        end

        function generated = generate( ...
                assignment,resourcePlan,carrier,config)
            if ~isa(resourcePlan,"sixgr.pdsch.PDSCHResourcePlan")
                error("sixgr:pdsch:MissingResourcePlan", ...
                    "Reference generation requires PDSCHResourcePlan.");
            end
            resolved = sixgr.pdsch.PDSCHReferenceSignalGenerator. ...
                resolveIndices(assignment,carrier,config);
            if strlength(resourcePlan.ReferenceConfigurationDigest) == 0
                error("sixgr:pdsch:UnboundReferenceConfiguration", ...
                    "The resource plan is not bound to an immutable " + ...
                    "reference-signal configuration digest.");
            end
            if resourcePlan.ReferenceConfigurationDigest ...
                    ~= config.ConfigurationDigest
                error("sixgr:pdsch:ReferenceConfigurationPlanMismatch", ...
                    "Resource plan and reference configuration digests differ.");
            end
            dmrsPlanMismatch = localCellIndexMismatch( ...
                resourcePlan.DMRSIndicesPerPort, ...
                resolved.DMRSIndicesPerPort);
            ptrsPlanMismatch = localActivePTRSPlanMismatch( ...
                resourcePlan.PTRSIndicesPerPort, ...
                resolved.PTRSIndicesPerPort, ...
                resourcePlan.ReservedUnionIndices);
            dmrsPortsMatch = isequal(resourcePlan.DMRSLogicalPortSet, ...
                resolved.DMRSLogicalPortSet);
            ptrsPortsMatch = isequal(resourcePlan.PTRSLogicalPortSet, ...
                resolved.PTRSLogicalPortSet);
            if dmrsPlanMismatch ~= 0 || ptrsPlanMismatch ~= 0 ...
                    || ~dmrsPortsMatch || ~ptrsPortsMatch
                error("sixgr:pdsch:ReferenceIndicesResourcePlanMismatch", ...
                    "Transmitter-generated DM-RS/PT-RS indices or logical " + ...
                    "ports differ from the authoritative resource plan " + ...
                    "(DM-RS mismatches=%g, PT-RS mismatches=%g, " + ...
                    "DM-RS ports match=%d, PT-RS ports match=%d).", ...
                    dmrsPlanMismatch,ptrsPlanMismatch, ...
                    dmrsPortsMatch,ptrsPortsMatch);
            end
            % The resolver produces the raw standard PT-RS pattern.
            % ReservedPRB/ReservedRE may deactivate a verified subset;
            % after the fail-closed subset check above, generation follows
            % the authoritative active resource plan.
            resolved.PTRSIndicesPerPort = ...
                resourcePlan.PTRSIndicesPerPort;

            reference = config.toStruct();
            pdsch = resolved.MaterializedPDSCH;
            dmrsValues = complex(nrPDSCHDMRS(carrier,pdsch));
            rankValue = double(assignment.get("NumLayers"));
            if isvector(dmrsValues) && rankValue == 1
                dmrsValues = dmrsValues(:);
            end
            if size(dmrsValues,2) ~= rankValue
                error("sixgr:pdsch:DMRSReferenceSymbolShapeMismatch", ...
                    "Generated DM-RS has %d columns for rank %d.", ...
                    size(dmrsValues,2),rankValue);
            end
            dmrsOracle = sixgr.pdsch.oracle.DMRSSequenceSpec. ...
                generate(struct( ...
                "DMRSConfigurationType", ...
                    double(reference.DMRSConfigurationType), ...
                "DMRSLength",double(reference.DMRSLength), ...
                "DMRSPortSet",double(assignment.get("DMRSPortSet")), ...
                "DMRSSymbols",resolved.DMRSSymbolPositions, ...
                "PRBSet",double(assignment.get( ...
                    "PRBSetCarrierRelative")), ...
                "NIDNSCID",double(reference.NIDNSCID), ...
                "NSCID",double(reference.NSCID), ...
                "SlotNumber",double(carrier.NSlot), ...
                "SymbolsPerSlot",double(carrier.SymbolsPerSlot)));
            dmrsNMSE = localNMSE(dmrsValues,dmrsOracle.Sequence);
            if dmrsNMSE > 1e-24
                dmrsNMSEPerPort = zeros(1,rankValue);
                for layer = 1:rankValue
                    dmrsNMSEPerPort(layer) = localNMSE( ...
                        dmrsValues(:,layer), ...
                        dmrsOracle.Sequence(:,layer));
                end
                error("sixgr:pdsch:DMRSIndependentSequenceMismatch", ...
                    "Generated DM-RS sequence has independent NMSE %.3g " + ...
                    "(configuration type %d, length %d, multiplexing %s, " + ...
                    "ports %s, symbols %s, PRBs %s, per-port NMSE %s).", ...
                    dmrsNMSE,double(reference.DMRSConfigurationType), ...
                    double(reference.DMRSLength), ...
                    char(string(reference.DMRSMultiplexing)), ...
                    mat2str(double(assignment.get("DMRSPortSet"))), ...
                    mat2str(double(resolved.DMRSSymbolPositions)), ...
                    mat2str(double(assignment.get( ...
                        "PRBSetCarrierRelative"))), ...
                    mat2str(dmrsNMSEPerPort,4));
            end
            dmrsCells = cell(1,rankValue);
            for layer = 1:rankValue
                dmrsCells{layer} = dmrsValues(:,layer) ...
                    .* double(reference.DMRSAmplitudeScale);
            end

            ptrsCells = repmat({complex(zeros(0,1))},1,rankValue);
            ptrsNMSE = 0;
            if logical(reference.EnablePTRS)
                densePDSCH = pdsch;
                densePDSCH.PTRS.TimeDensity = 1;
                denseSubscripts = nrPDSCHPTRSIndices( ...
                    carrier,densePDSCH,"IndexStyle","subscript", ...
                    "IndexBase","0based");
                denseValues = complex(nrPDSCHPTRS(carrier,densePDSCH));
                associatedPort = double(assignment.get("PTRSPortSet"));
                layer = find(double(assignment.get("DMRSPortSet")) ...
                    == associatedPort,1);
                K = double(carrier.NSizeGrid)*12;
                % Toolbox subscript column 3 is the zero-based layer
                % ordinal, not the configured logical DM-RS port number.
                denseMask = double(denseSubscripts(:,3)) == (layer-1);
                denseIndices = double(denseSubscripts(denseMask,1) ...
                    + K*denseSubscripts(denseMask,2));
                denseValues = denseValues(:,1);
                [present,catalogPosition] = ismember( ...
                    double(resolved.PTRSIndicesPerPort{layer}(:)), ...
                    denseIndices(:));
                if any(~present)
                    error("sixgr:pdsch:PTRSReferenceSymbolCatalogMismatch", ...
                        "An independently resolved PT-RS index is absent " + ...
                        "from the dense Toolbox symbol catalog.");
                end
                ptrsValues = denseValues(catalogPosition);
                expectedCount = numel(resolved.PTRSIndicesPerPort{layer});
                if numel(ptrsValues) ~= expectedCount
                    error("sixgr:pdsch:PTRSReferenceSymbolShapeMismatch", ...
                        "Generated PT-RS symbol/index counts differ.");
                end
                ptrsOracle = sixgr.pdsch.oracle.PTRSSequenceSpec. ...
                    generate(struct( ...
                    "Indices0Based", ...
                        resolved.PTRSIndicesPerPort{layer}, ...
                    "GridNumPRB",double(carrier.NSizeGrid), ...
                    "PRBSet",double(assignment.get( ...
                        "PRBSetCarrierRelative")), ...
                    "DMRSConfigurationType", ...
                        double(reference.DMRSConfigurationType), ...
                    "AssociatedDMRSPort",associatedPort, ...
                    "NIDNSCID",double(reference.NIDNSCID), ...
                    "NSCID",double(reference.NSCID), ...
                    "ReferenceDMRSSymbol", ...
                        resolved.DMRSSymbolPositions(1), ...
                    "SlotNumber",double(carrier.NSlot), ...
                    "SymbolsPerSlot",double(carrier.SymbolsPerSlot)));
                ptrsNMSE = localNMSE(ptrsValues,ptrsOracle.Sequence);
                if ptrsNMSE > 1e-24
                    error("sixgr:pdsch:PTRSIndependentSequenceMismatch", ...
                        "Generated PT-RS sequence has independent NMSE %.3g.", ...
                        ptrsNMSE);
                end
                ptrsCells{layer} = ptrsValues ...
                    .* double(reference.PTRSAmplitudeScale);
            end
            generated = resolved;
            generated.DMRSSymbolsPerPort = dmrsCells;
            generated.PTRSSymbolsPerPort = ptrsCells;
            generated.DMRSSequenceNMSE = dmrsNMSE;
            generated.PTRSSequenceNMSE = ptrsNMSE;
            generated.NPhysicalTxAntennas = ...
                double(reference.NPhysicalTxAntennas);
            generated.OFDMOptions = reference.OFDMOptions;
            generated.Source = ...
                "transmitter_generated+independently_validated";
        end
    end
end

function localRequireInputs(assignment,carrier,config)
if ~isa(assignment,"sixgr.pdsch.PDSCHSchedulingAssignment")
    error("sixgr:pdsch:MissingSchedulingAssignment", ...
        "Reference generation requires PDSCHSchedulingAssignment.");
end
if ~isa(carrier,"nrCarrierConfig")
    error("sixgr:pdsch:InvalidCarrier", ...
        "Reference generation requires nrCarrierConfig.");
end
if ~isa(config,"sixgr.pdsch.PDSCHReferenceSignalConfig")
    error("sixgr:pdsch:MissingImmutableReferenceConfiguration", ...
        "Reference generation requires an immutable " + ...
        "PDSCHReferenceSignalConfig.");
end
end

function validation = localValidateDMRS(assignment,reference)
allocation = double(assignment.get("SymbolAllocation"));
validation = sixgr.pdsch.PDSCHDMRSValidator. ...
    validateConfiguration(struct( ...
    "MappingType",string(assignment.get("MappingType")), ...
    "DMRSLength",double(reference.DMRSLength), ...
    "PDSCHStartSymbol",allocation(1), ...
    "PDSCHDurationLd",allocation(2), ...
    "DMRSTypeAPosition",double(reference.DMRSTypeAPosition), ...
    "DMRSAdditionalPosition",double(reference.DMRSAdditionalPosition), ...
    "DMRSConfigurationType",double(reference.DMRSConfigurationType), ...
    "DMRSMultiplexing",string(reference.DMRSMultiplexing), ...
    "DMRSPortSet",double(assignment.get("DMRSPortSet")), ...
    "NumLayers",double(assignment.get("NumLayers")), ...
    "NumCDMGroupsWithoutData", ...
        double(reference.NumCDMGroupsWithoutData), ...
    "NIDNSCID",double(reference.NIDNSCID), ...
    "NSCID",double(reference.NSCID)));
end

function [cells,subscripts] = localDMRSIndices(carrier,pdsch,ports)
subscripts = nrPDSCHDMRSIndices(carrier,pdsch, ...
    "IndexStyle","subscript","IndexBase","0based");
K = double(carrier.NSizeGrid)*12;
cells = cell(1,numel(ports));
for layer = 1:numel(ports)
    % Toolbox subscript column 3 enumerates configured layers from zero;
    % logical DM-RS port identifiers may be nonconsecutive (for example,
    % ports 0:5 followed by port 12).
    mask = double(subscripts(:,3)) == (layer-1);
    cells{layer} = double(subscripts(mask,1) ...
        + K*subscripts(mask,2)).';
    if isempty(cells{layer})
        error("sixgr:pdsch:DMRSLogicalPortNotMaterialized", ...
            "Toolbox did not materialize configured logical DM-RS port %d.", ...
            ports(layer));
    end
end
end

function [cells,subscripts] = localPTRSIndices( ...
        carrier,pdsch,dmrsPorts,ptrsPort)
subscripts = nrPDSCHPTRSIndices(carrier,pdsch, ...
    "IndexStyle","subscript","IndexBase","0based");
K = double(carrier.NSizeGrid)*12;
cells = repmat({zeros(1,0)},1,numel(dmrsPorts));
layer = find(dmrsPorts == ptrsPort,1);
% PT-RS is reported on its associated layer ordinal, not its logical port.
mask = double(subscripts(:,3)) == (layer-1);
if ~any(mask)
    error("sixgr:pdsch:PTRSLogicalPortNotMaterialized", ...
        "Toolbox did not materialize configured logical PT-RS port %d.", ...
        ptrsPort);
end
cells{layer} = double(subscripts(mask,1) ...
    + K*subscripts(mask,2)).';
end

function request = localPTRSIndexRequest( ...
        assignment,carrier,reference,dmrsSymbols)
request = struct( ...
    "PRBSet",double(assignment.get("PRBSetCarrierRelative")), ...
    "SymbolAllocation",double(assignment.get("SymbolAllocation")), ...
    "DMRSSymbols",double(dmrsSymbols), ...
    "TimeDensity",double(reference.PTRSTimeDensity), ...
    "FrequencyDensity",double(reference.PTRSFrequencyDensity), ...
    "REOffset",string(reference.PTRSREOffset), ...
    "GridNumPRB",double(carrier.NSizeGrid), ...
    "RNTI",double(assignment.get("RNTI")), ...
    "DMRSConfigurationType", ...
        double(reference.DMRSConfigurationType), ...
    "AssociatedDMRSPort",double(assignment.get("PTRSPortSet")));
end

function count = localCellIndexMismatch(a,b)
if ~iscell(a) || ~iscell(b) || numel(a) ~= numel(b)
    count = inf;
    return;
end
count = 0;
for i = 1:numel(a)
    count = count + localIndexMismatch(a{i},b{i});
end
end

function count = localActivePTRSPlanMismatch(planned,raw,reserved)
if ~iscell(planned) || ~iscell(raw) || numel(planned) ~= numel(raw)
    count = inf;
    return;
end
reserved = double(reserved(:));
count = 0;
for i = 1:numel(raw)
    rawIndices = double(raw{i}(:));
    plannedIndices = double(planned{i}(:));
    if any(~ismember(plannedIndices,rawIndices))
        count = count + nnz(~ismember(plannedIndices,rawIndices));
        continue;
    end
    activeRaw = rawIndices(ismember(rawIndices,plannedIndices));
    if ~isequal(activeRaw,plannedIndices)
        count = count + localIndexMismatch(activeRaw,plannedIndices);
    end
    omitted = rawIndices(~ismember(rawIndices,plannedIndices));
    count = count + nnz(~ismember(omitted,reserved));
end
end

function count = localIndexMismatch(a,b)
a = double(a(:));
b = double(b(:));
count = numel(setxor(a,b));
end

function value = localNMSE(actual,expected)
actual = complex(double(actual));
expected = complex(double(expected));
if ~isequal(size(actual),size(expected))
    value = inf;
    return;
end
denominator = max(sum(abs(expected(:)).^2),eps);
value = sum(abs(actual(:)-expected(:)).^2)/denominator;
end
