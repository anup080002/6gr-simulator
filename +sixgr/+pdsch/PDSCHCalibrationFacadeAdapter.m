function [indices, symbols] = localDMRS(carrier, pdsch, ports, scale)
sub = nrPDSCHDMRSIndices(carrier, pdsch, ...
    "IndexStyle", "subscript", "IndexBase", "0based");
values = complex(nrPDSCHDMRS(carrier, pdsch)) .* double(scale);
K = double(carrier.NSizeGrid) * 12;
indices = cell(1, numel(ports));
symbols = cell(1, numel(ports));
for layer = 1:numel(ports)
    % Toolbox subscript column 3 is the zero-based layer ordinal, not
    % the configured logical DM-RS port identifier.
    mask = double(sub(:,3)) == (layer-1);
    indices{layer} = double(sub(mask,1) + K * sub(mask,2)).';
    symbols{layer} = complex(values(:,layer));
    if numel(indices{layer}) ~= numel(symbols{layer})
        error("sixgr:pdsch:CalibrationDMRSShapeMismatch", ...
            "DM-RS index/symbol counts differ for logical port %d.", ...
            ports(layer));
    end
end
end

function [indices, symbols, ports] = localPTRS(carrier, pdsch, rankValue)
indices = repmat({zeros(1,0)}, 1, rankValue);
symbols = repmat({complex(zeros(0,1))}, 1, rankValue);
ports = zeros(1,0);
if ~logical(pdsch.EnablePTRS)
    return;
end
dmrsPorts = double(pdsch.DMRS.DMRSPortSet(:).');
ports = double(pdsch.PTRS.PTRSPortSet(:).');
if numel(ports) ~= 1
    error("sixgr:pdsch:InvalidPTRSPortAssociation", ...
        "Calibration PT-RS requires one logical port.");
end
layer = find(dmrsPorts == ports,1);
if isempty(layer) || layer > rankValue
    error("sixgr:pdsch:InvalidPTRSPortAssociation", ...
        "PT-RS port %d has no scheduled layer.",ports);
end
dmrsSub = nrPDSCHDMRSIndices(carrier,pdsch, ...
    "IndexStyle","subscript","IndexBase","0based");
if isempty(dmrsSub)
    detail = sprintf([ ...
        'PT-RS cannot be materialized because the replay PDSCH has no ' ...
        'active DM-RS RE. SymbolAllocation=%s MappingType=%s ' ...
        'DMRSTypeAPosition=%g DMRSAdditionalPosition=%g DMRSLength=%g ' ...
        'PRBCount=%d NumLayers=%d.'], ...
        mat2str(double(pdsch.SymbolAllocation(:).')), ...
        char(string(pdsch.MappingType)), ...
        double(pdsch.DMRS.DMRSTypeAPosition), ...
        double(pdsch.DMRS.DMRSAdditionalPosition), ...
        double(pdsch.DMRS.DMRSLength), ...
        numel(pdsch.PRBSet), double(pdsch.NumLayers));
    error("sixgr:pdsch:PTRSRequiresActiveDMRS", "%s", detail);
end
request = struct( ...
    "PRBSet",double(pdsch.PRBSet(:).'), ...
    "SymbolAllocation",double(pdsch.SymbolAllocation(:).'), ...
    "DMRSSymbols",unique(double(dmrsSub(:,2))).', ...
    "TimeDensity",double(pdsch.PTRS.TimeDensity), ...
    "FrequencyDensity",double(pdsch.PTRS.FrequencyDensity), ...
    "REOffset",string(pdsch.PTRS.REOffset), ...
    "GridNumPRB",double(carrier.NSizeGrid), ...
    "RNTI",double(pdsch.RNTI), ...
    "DMRSConfigurationType", ...
        double(pdsch.DMRS.DMRSConfigurationType), ...
    "AssociatedDMRSPort",ports);
resolved = sixgr.pdsch.PDSCHPTRSResolver.resolveIndices(request);
toolboxSub = nrPDSCHPTRSIndices(carrier,pdsch, ...
    "IndexStyle","subscript","IndexBase","0based");
toolboxValues = complex(nrPDSCHPTRS(carrier,pdsch));
K = double(carrier.NSizeGrid)*12;
toolboxMask = double(toolboxSub(:,3)) == (layer-1);
toolboxIndices = double(toolboxSub(toolboxMask,1) ...
    + K*toolboxSub(toolboxMask,2));
resolvedIndices = double(resolved.Indices0Based(:));
if any(~ismember(toolboxIndices,resolvedIndices))
    error("sixgr:pdsch:PTRSReferenceSymbolCatalogMismatch", ...
        "The active Toolbox PT-RS catalog contains an index absent " + ...
        "from the independently resolved canonical PT-RS plan.");
end
% ReservedPRB/ReservedRE can legally deactivate a subset of the raw
% standard PT-RS pattern.  Retain canonical ordering while applying that
% explicit active-resource mask, then require exact Toolbox agreement.
activeResolved = resolvedIndices(ismember( ...
    resolvedIndices,toolboxIndices));
if ~isequal(activeResolved,toolboxIndices(:))
    error("sixgr:pdsch:PTRSActiveResourceMismatch", ...
        "Canonical and Toolbox active PT-RS index ordering differs.");
end
values = toolboxValues(:);
if numel(values) ~= numel(activeResolved)
    error("sixgr:pdsch:PTRSReferenceSymbolShapeMismatch", ...
        "Toolbox PT-RS symbol count differs from the active canonical " + ...
        "PT-RS index plan.");
end
indices{layer} = activeResolved(:).';
symbols{layer} = values(:);
end

