    capabilityVariantSource = ...
        "adapter.explicit_non_1024_empty_capability_variant";
end
capabilityVariant = string(capabilityVariant);
if ~isscalar(capabilityVariant)
    error("sixgr:pdsch:Invalid1024QAMCapabilityVariant", ...
        "UECapability1024QAMVariant must be a string scalar.");
end
ownership.UECapability1024QAMVariant = capabilityVariant;

[maxMIMOLayers, maxMIMOLayersSource] = localFirstPresent( ...
    contextRoot, [ ...
    "MaxNumberMIMOLayersPDSCH", ...
    "MCSContext.MaxNumberMIMOLayersPDSCH", ...
