    "UECapability1024QAM","RRCEnabled1024QAM", ...
    "DCIEnabled1024QAM","DeploymentAllows1024QAM", ...
    "FrequencyRangeAllows1024QAM","BandAllows1024QAM"];
logicalPaths = { ...
    ["UECapability1024QAM", ...
     "MCSContext.UECapability1024QAM", ...
     "LegacyGrantSnapshot.UECapability1024QAM", ...
     "LegacyGrantSnapshot.MCSContext.UECapability1024QAM", ...
