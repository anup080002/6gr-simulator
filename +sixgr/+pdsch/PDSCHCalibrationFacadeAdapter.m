classdef PDSCHCalibrationFacadeAdapter
    %PDSCHCALIBRATIONFACADEADAPTER Freeze legacy calibration inputs.
    %
    % This adapter is the only bridge from the configuration-oriented
    % PDSCH_Tx/PDSCH_Rx signatures to the canonical assignment-owned
    % production chain.  It performs no coding, scrambling, modulation,
    % layer mapping, precoding, grid mapping, OFDM processing, channel
    % estimation, equalization, or decoding.

    methods (Static)
        function ownership = resolveMCSOwnership(cfg, phyGrant, numCodewords)
            arguments
                cfg (1,1) struct
                phyGrant (1,1) struct
                numCodewords (1,1) double {mustBeInteger,mustBeInRange(numCodewords,1,2)}
            end
            ownership = localResolveMCSOwnership( ...
                cfg, phyGrant, numCodewords);
        end

        function bundle = materialize(cfg, carrier, pdsch, request)
            arguments
                cfg (1,1) struct
                carrier (1,1) nrCarrierConfig
                pdsch (1,1) nrPDSCHConfig
                request (1,1) struct
            end

            request = localValidateRequest(request);
            [modulation, layerCount] = localCodewordGeometry(pdsch);
            numCodewords = numel(layerCount);
            if double(request.NumLayers) ~= double(pdsch.NumLayers)
                error("sixgr:pdsch:CalibrationNumLayersMismatch", ...
                    ("Calibration MCS context NumLayers must equal the " + ...
                    "materialized PDSCH rank."));
            end
            receiverOnly = logical(request.ReceiverOnly);
            suppliedCodingPlans = localSuppliedCodingPlans( ...
                request.CodingPlans, numCodewords, receiverOnly);
            if receiverOnly
                targetRateRequested = cellfun( ...
                    @(plan) double(plan.TargetCodeRate), ...
                    suppliedCodingPlans);
                rv = cellfun(@(plan) double(plan.RV), ...
                    suppliedCodingPlans);
                localAssertOptionalExactVector( ...
                    request.TargetCodeRate, targetRateRequested, ...
                    "sixgr:pdsch:CalibrationCodingPlanRateMismatch", ...
                    "TargetCodeRate");
                localAssertOptionalExactVector( ...
                    request.RV, rv, ...
                    "sixgr:pdsch:CalibrationCodingPlanRVMismatch", ...
                    "RV");
            else
                targetRateRequested = localExactPerCodeword( ...
                    request.TargetCodeRate, numCodewords, ...
                    "sixgr:pdsch:CalibrationCodeRateCountMismatch");
                rv = localPerCodeword(request.RV, numCodewords, ...
                    "sixgr:pdsch:CalibrationRVCountMismatch");
            end
            if any(rv ~= fix(rv) | rv < 0 | rv > 3)
                error("sixgr:phy:dl:PDSCHBadRV", ...
                    "Calibration PDSCH RV must contain integers in [0,3].");
            end
            xOverhead = double(request.XOverhead);
            if ~(isscalar(xOverhead) && isfinite(xOverhead) ...
                    && ismember(xOverhead, [0 6 12 18]))
                error("sixgr:pdsch:InvalidXOverhead", ...
                    "Calibration XOverhead must be one of 0, 6, 12, or 18.");
            end

            [mcsTable, mcsIndex, mcsProfiles] = ...
                localExactTableBackedMCS(request, modulation, ...
                targetRateRequested);
            targetRate = double([mcsProfiles.TargetCodeRate]);
            qm = double([mcsProfiles.Qm]);

            ports = double(pdsch.DMRS.DMRSPortSet(:).');
            if isempty(ports)
                policy = string(request.DMRSPortResolutionPolicy);
                if policy ~= ...
                        "explicit_calibration_rank_order_ports"
                    error("sixgr:pdsch:MissingCalibrationDMRSPortSet", ...
                        "Calibration requires an explicit DM-RS port set " + ...
                        "or the named explicit_calibration_rank_order_ports " + ...
                        "factory policy.");
                end
                % The named calibration policy is frozen into provenance;
                % canonical execution never sees an empty/unowned default.
                ports = 0:(double(pdsch.NumLayers) - 1);
                pdsch.DMRS.DMRSPortSet = ports;
            end
            if numel(ports) ~= double(pdsch.NumLayers)
                error("sixgr:pdsch:DMRSPortLayerCountMismatch", ...
                    "Calibration requires one explicit DM-RS port per layer.");
            end

            [dmrsIndices, dmrsSymbols] = localDMRS( ...
                carrier, pdsch, ports, request.DMRSAmplitudeScale);
            [ptrsIndices, ptrsSymbols, ptrsPorts] = localPTRS( ...
                carrier, pdsch, double(pdsch.NumLayers));
            [dataIndices, dataIndicesInfo] = ...
                localDataIndices(carrier, pdsch);
            allocation = localAllocation(carrier, ...
                double(pdsch.PRBSet(:).'), ...
                double(pdsch.SymbolAllocation(:).'));
            referenceUnion = unique( ...
                [dmrsIndices{:}, ptrsIndices{:}], "sorted");
            accounted = unique([dataIndices, referenceUnion], "sorted");
            implicitReserved = setdiff(allocation, accounted, "stable");
            explicitReserved = double(request.ReservedREZeroBased(:).');
            if any(~ismember(explicitReserved, allocation))
                error("sixgr:pdsch:ReservedREOutsideAllocation", ...
                    "A calibration reservation lies outside the PDSCH allocation.");
            end
            reservation = unique( ...
                [implicitReserved, explicitReserved], "sorted");
            ownership = sixgr.pdsch.PDSCHResourceOwnershipMap( ...
                allocation, struct("Other", reservation));

            [legacyPrecoder, precoderBundle] = localPrecoder( ...
                cfg, pdsch, request.PrecodingMatrix);
            nPhysicalPorts = double(legacyPrecoder.NumWaveformColumns);
            if isempty(precoderBundle)
                nPhysicalPorts = double(pdsch.NumLayers);
            end
            [windowingSamples, windowingInfo] = ...
                sixgr.phy.waveform.resolveOFDMWindowing(cfg, carrier);
            referenceData = localMaterializerReference(carrier,pdsch);
            referenceData.DataScramblingIdentityNID = double(pdsch.NID);
            referenceData.DMRSMultiplexing = char(string( ...
                sixgr.util.structGet(cfg, ...
                "phy.pdsch.dmrs.multiplexing", "basic")));
            referenceData.NPhysicalTxAntennas = nPhysicalPorts;
            referenceData.OFDMOptions = { ...
                "Windowing", double(windowingSamples)};
            referenceData.DMRSAmplitudeScale = ...
                double(request.DMRSAmplitudeScale);
            referenceData.PTRSAmplitudeScale = 1;
            referenceConfig = ...
                sixgr.pdsch.PDSCHReferenceSignalConfig(referenceData);

            provisionalContext = localPlanContext( ...
                carrier, pdsch, dmrsIndices, ptrsIndices, ...
                ports, layerCount, qm, ones(1, numCodewords), ...
                referenceConfig.ConfigurationDigest);
            provisionalPlan = sixgr.pdsch.PDSCHResourcePlan( ...
                ownership, provisionalContext);
            if ~isequal(double(provisionalPlan.DataIndices(:).'), ...
                    double(dataIndices(:).'))
                error("sixgr:pdsch:CalibrationResourcePlanMismatch", ...
                    "The immutable calibration resource plan differs from " + ...
                    "the final PDSCH data-index kernel output.");
            end

            if receiverOnly
                tbs = cellfun( ...
                    @(plan) double(plan.TransportBlockSize), ...
                    suppliedCodingPlans);
                scheduledTBS = tbs;
                localAssertOptionalExactVector( ...
                    request.TransportBlockSizes, tbs, ...
                    "sixgr:pdsch:CalibrationCodingPlanTBSMismatch", ...
                    "TransportBlockSizes");
            else
                [scheduledTBS, tbs] = localTransportBlockSizes( ...
                    pdsch, provisionalPlan, ...
                    double(dataIndicesInfo.NREPerPRB), ...
                    targetRateRequested, xOverhead, ...
                    request.TransportBlockSizes);
            end
            nrePerPRBForTBS = localNREPerPRBForTBS( ...
                dataIndicesInfo.NREPerPRB);
            codingPlans = cell(1, numCodewords);
            codeBlockCounts = zeros(1, numCodewords);
            for cw = 1:numCodewords
                if receiverOnly
                    codingPlans{cw} = suppliedCodingPlans{cw};
                    localAssertSuppliedCodingPlan( ...
                        codingPlans{cw}, cw - 1, tbs(cw), ...
                        targetRate(cw), ...
                        provisionalPlan.GPerCodeword(cw), rv(cw), ...
                        modulation(cw), layerCount(cw));
                else
                    codingPlans{cw} = sixgr.pdsch.DLSCHCodingPlan.resolve( ...
                        "TransportBlockSize", tbs(cw), ...
                        "TargetCodeRate", targetRate(cw), ...
                        "RateMatchedBitCount", ...
                            provisionalPlan.GPerCodeword(cw), ...
                        "RV", rv(cw), ...
                        "Modulation", modulation(cw), ...
                        "NumLayers", layerCount(cw), ...
                        "CodewordIndex", cw - 1);
                end
                codeBlockCounts(cw) = ...
                    double(codingPlans{cw}.NumCodeBlocks);
            end
            finalContext = provisionalContext;
            finalContext.CodeBlockCountPerCodeword = codeBlockCounts;
            resourcePlan = sixgr.pdsch.PDSCHResourcePlan( ...
                ownership, finalContext);
            if ~isequal(resourcePlan.GPerCodeword, ...
                    provisionalPlan.GPerCodeword)
                error("sixgr:pdsch:CalibrationGContractMutation", ...
                    "Code-block resolution changed the exact G contract.");
            end

            assignmentRequest = localAssignmentRequest( ...
                carrier, pdsch, mcsTable, mcsIndex, mcsProfiles, ...
                layerCount, ports, ptrsPorts, rv, xOverhead, request);
            absoluteSlot = localAbsoluteSlot(carrier);
            if request.ExecutionProfile == "scheduler_truth"
                assignmentRequest = localApplySchedulerTruthAssignmentContext( ...
                    assignmentRequest, request.SchedulerGrantContext, absoluteSlot);
                assignment = sixgr.pdsch.PDSCHAssignmentFactory.forSchedulerTruth( ...
                    assignmentRequest, struct( ...
                        "AbsoluteSlot", absoluteSlot, ...
                        "ResourceAvailable", true));
            else
                assignment = sixgr.pdsch.PDSCHAssignmentFactory.forCalibration( ...
                    assignmentRequest, struct( ...
                        "AbsoluteSlot", absoluteSlot, ...
                        "ResourceAvailable", true));
            end

            materializedPDSCH = ...
                sixgr.pdsch.PDSCHConfigMaterializer.fromAssignment( ...
                    assignment, referenceData);
            localAssertPDSCHUnchanged(materializedPDSCH, pdsch);

            transportBlocks = localTransportBlocks( ...
                request.TransportBlockBits, tbs, ...
                receiverOnly);
            receiverConfig = localReceiverConfig( ...
                cfg, request, tbs, nPhysicalPorts, ...
                legacyPrecoder, carrier, referenceConfig);

            bundle = struct( ...
                "ContractVersion", ...
                    "PDSCHExplicitGrantFacadeAdapter/v2", ...
                "Assignment", assignment, ...
                "ResourcePlan", resourcePlan, ...
                "Carrier", carrier, ...
                "PDSCH", pdsch, ...
                "ReferenceConfig", referenceConfig, ...
                "ReferenceData", referenceData, ...
                "ReceiverConfig", receiverConfig, ...
                "PrecoderBundle", precoderBundle, ...
                "LegacyPrecoder", legacyPrecoder, ...
                "TransportBlocks", {transportBlocks}, ...
                "TransportBlockSizes", tbs, ...
                "ScheduledTransportBlockSizes", scheduledTBS, ...
                "NREPerPRBForTBS", nrePerPRBForTBS, ...
                "RequestedTargetCodeRate", targetRateRequested, ...
                "TargetCodeRate", targetRate, ...
                "RV", rv, ...
                "XOverhead", xOverhead, ...
                "CodingPlans", {codingPlans}, ...
                "DMRSIndicesPerPort", {dmrsIndices}, ...
                "DMRSSymbolsPerPort", {dmrsSymbols}, ...
                "PTRSIndicesPerPort", {ptrsIndices}, ...
                "PTRSSymbolsPerPort", {ptrsSymbols}, ...
                "WindowingInfo", windowingInfo, ...
                "DMRSPortResolutionPolicy", ...
                    string(request.DMRSPortResolutionPolicy), ...
                "Source", localExplicitGrantAdapterSource( ...
                    request.ExecutionProfile));
        end
    end
end

function ownership = localResolveMCSOwnership(cfg, phyGrant, count)
hasGrant = ~isempty(fieldnames(phyGrant));
if hasGrant
    [tables, tableSource] = localFirstPresent(phyGrant, [ ...
        "CodingLayout.MCSTablePerCodeword", ...
        "MCSTablePerCodeword", ...
        "CodingLayout.MCSTable", ...
        "MCSTable"]);
    [indices, indexSource] = localFirstPresent(phyGrant, [ ...
        "CodingLayout.MCSIndexPerCodeword", ...
        "MCSIndexPerCodeword", ...
        "CodingLayout.MCSIndex", ...
        "MCSIndex", "MCS"]);
    ownerPrefix = "PHYGrant.";
else
    [tables, tableSource] = localFirstPresent(cfg, [ ...
        "phy.pdsch.mcsTablePerCodeword", ...
        "phy.pdsch.mcsTable"]);
    [indices, indexSource] = localFirstPresent(cfg, [ ...
        "phy.pdsch.mcsIndexPerCodeword", ...
        "phy.pdsch.mcsIndex", ...
        "phy.pdsch.configuredMCSIndex"]);
    ownerPrefix = "cfg.";
end
tables = string(tables);
tables = tables(:).';
indices = double(indices(:).');
if numel(tables) ~= count || any(strlength(strtrim(tables)) == 0)
    error("sixgr:pdsch:MissingCodewordSpecificMCS", ...
        "%s calibration ownership must provide exactly %d explicit " + ...
        "MCS table token(s), one per codeword.", ...
        ownerPrefix, count);
end
if numel(indices) ~= count || any(~isfinite(indices) ...
        | indices ~= fix(indices) | indices < 0)
    error("sixgr:pdsch:MissingCodewordSpecificMCS", ...
        "%s calibration ownership must provide exactly %d explicit " + ...
        "nonnegative integer MCS index token(s), one per codeword.", ...
        ownerPrefix, count);
end

