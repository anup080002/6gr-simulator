     "LegacyGrantSnapshot.MCSContext.RRCEnabled1024QAM", ...
     "phy.pdsch.RRCEnabled1024QAM", ...
     "phy.pdsch.mcsContext.RRCEnabled1024QAM"], ...
    ["DCIEnabled1024QAM", ...
     "MCSContext.DCIEnabled1024QAM", ...
     "LegacyGrantSnapshot.DCIEnabled1024QAM", ...
     "LegacyGrantSnapshot.MCSContext.DCIEnabled1024QAM", ...
     "phy.pdsch.DCIEnabled1024QAM", ...
     "phy.pdsch.mcsContext.DCIEnabled1024QAM"], ...
    ["DeploymentAllows1024QAM", ...
     "MCSContext.DeploymentAllows1024QAM", ...
     "LegacyGrantSnapshot.DeploymentAllows1024QAM", ...
     "LegacyGrantSnapshot.MCSContext.DeploymentAllows1024QAM", ...
     "phy.pdsch.DeploymentAllows1024QAM", ...
     "phy.pdsch.mcsContext.DeploymentAllows1024QAM"], ...
    ["FrequencyRangeAllows1024QAM", ...
     "MCSContext.FrequencyRangeAllows1024QAM", ...
     "LegacyGrantSnapshot.FrequencyRangeAllows1024QAM", ...
     "LegacyGrantSnapshot.MCSContext.FrequencyRangeAllows1024QAM", ...
     "phy.pdsch.FrequencyRangeAllows1024QAM", ...
     "phy.pdsch.mcsContext.FrequencyRangeAllows1024QAM"], ...
    ["BandAllows1024QAM", ...
     "MCSContext.BandAllows1024QAM", ...
     "LegacyGrantSnapshot.BandAllows1024QAM", ...
     "LegacyGrantSnapshot.MCSContext.BandAllows1024QAM", ...
     "phy.pdsch.BandAllows1024QAM", ...
     "phy.pdsch.mcsContext.BandAllows1024QAM"]};
if hasGrant
    contextRoot = phyGrant;
else
    contextRoot = cfg;
end
contextSources = strings(1,numel(logicalNames));
for idx = 1:numel(logicalNames)
    [value, source] = localFirstPresent( ...
        contextRoot, logicalPaths{idx});
    if isempty(value) && hasGrant
        [value, source] = localFirstPresent(cfg, [ ...
            "phy.pdsch." + logicalNames(idx), ...
            "phy.pdsch.mcsContext." + logicalNames(idx)]);
        if ~isempty(value)
            source = "cfg." + source;
        end
    end
    if isempty(value)
        error("sixgr:pdsch:Incomplete1024QAMCapabilityContext", ...
            "Calibration ownership must explicitly provide %s as a " + ...
            "logical scalar, including when the selected MCS is below " + ...
            "1024QAM.", logicalNames(idx));
    end
    if ~(islogical(value) && isscalar(value))
        error("sixgr:pdsch:Invalid1024QAMCapabilityContext", ...
            "%s must be an explicit logical scalar.", logicalNames(idx));
    end
    ownership.(logicalNames(idx)) = value;
    contextSources(idx) = source;
end

