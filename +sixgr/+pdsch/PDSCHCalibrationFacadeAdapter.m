function localAssertSuppliedCodingPlan(plan,codewordIndex,tbs,rate,g,rv, ...
        modulation,numLayers)
matches = double(plan.CodewordIndex) == double(codewordIndex) ...
    && double(plan.TransportBlockSize) == double(tbs) ...
    && abs(double(plan.TargetCodeRate)-double(rate)) <= 1e-12 ...
    && double(plan.RateMatchedBitCount) == double(g) ...
    && double(plan.RV) == double(rv) ...
    && upper(string(plan.Modulation)) == upper(string(modulation)) ...
    && double(plan.NumLayers) == double(numLayers);
if ~matches
    error("sixgr:pdsch:CalibrationReceiverCodingPlanMismatch", ...
        ("Calibration RX coding plan %d differs from the immutable " + ...
        "assignment/resource/codeword contract."),codewordIndex);
end
layout = plan.toCodingLayout();
required = ["BaseGraph","FillerPositions","RV", ...
    "TransportBlockSize","RateMatchedBitCount","CodingLayoutHash"];
missing = required(~isfield(layout,required));
if ~isempty(missing)
    error("sixgr:pdsch:CalibrationReceiverIncompleteCodingPlan", ...
        "Coding plan %d layout is missing: %s.",codewordIndex, ...
        strjoin(cellstr(missing),", "));
end
if string(layout.CodingLayoutHash) ~= string(plan.CodingLayoutHash)
    error("sixgr:pdsch:CalibrationReceiverCodingPlanMismatch", ...
        "Coding plan %d layout hash does not match its immutable identity.", ...
        codewordIndex);
end
end

