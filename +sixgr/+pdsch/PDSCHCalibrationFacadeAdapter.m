if pdsch.EnablePTRS
    reference.PTRSTimeDensity = double(pdsch.PTRS.TimeDensity);
    reference.PTRSFrequencyDensity = ...
        double(pdsch.PTRS.FrequencyDensity);
    reference.PTRSREOffset = string(pdsch.PTRS.REOffset);
end
end

function localAssertPDSCHUnchanged(actual, expected)
numeric = ["PRBSet","SymbolAllocation","NumLayers","RNTI","NID"];
for idx = 1:numel(numeric)
    name = numeric(idx);
    if ~isequal(double(actual.(name)), double(expected.(name)))
        error("sixgr:pdsch:CalibrationMaterializationMismatch", ...
            "Assignment materialization changed PDSCH.%s.", name);
    end
end
if ~isequal(upper(string(actual.Modulation)), ...
        upper(string(expected.Modulation))) ...
        || upper(string(actual.MappingType)) ...
            ~= upper(string(expected.MappingType))
    error("sixgr:pdsch:CalibrationMaterializationMismatch", ...
        "Assignment materialization changed modulation or mapping type.");
end
end

function [legacy, bundle] = localPrecoder(cfg, pdsch, matrix)
legacy = sixgr.phy.dl.resolvePDSCHPrecoding(pdsch, cfg, ...
    "PrecodingMatrix", matrix);
bundle = [];
if ~logical(legacy.Active)
    return;
end
prbs = double(pdsch.PRBSet(:).');
symbols = double(pdsch.SymbolAllocation(1)) ...
    + (0:(double(pdsch.SymbolAllocation(2)) - 1));
nPRG = double(legacy.NumPRG);
if nPRG == 1
    mode = "wideband_fixed_matrix";
    prgSize = 0;
else
    mode = "prg_noncodebook";
    prgSize = numel(prbs) / nPRG;
    if prgSize ~= fix(prgSize) || prgSize < 1
        error("sixgr:pdsch:PDSCHPrecoderBundle:IncompletePRGCoverage", ...
            "Calibration PRG pages must partition the scheduled PRBs " + ...
            "exactly.");
    end
end
normalization = lower(strtrim(string(sixgr.util.structGet(legacy, ...
    "NormalizationConvention", "explicit_no_normalization"))));
spec = struct( ...
    "Mode", mode, ...
    "NPorts", double(legacy.NumWaveformColumns), ...
    "NLayers", double(pdsch.NumLayers), ...
    "NPRG", nPRG, "NSymbolGroups", 1, ...
    "PRGSize", prgSize, "PRBSet", prbs, ...
    "ScheduledSymbols", symbols, ...
    "SymbolGroupMap", zeros(1,numel(symbols)), ...
    "W", reshape(complex(double(legacy.MatrixPortsPerPRG)), ...
        [size(legacy.MatrixPortsPerPRG,1), ...
         size(legacy.MatrixPortsPerPRG,2), nPRG, 1]), ...
    "MatrixSource", "calibration_" + string(legacy.Source), ...
    "CodebookIdentifier", "", ...
    "NormalizationConvention", normalization, ...
    "NormalizationTolerance", 1e-10);
bundle = sixgr.pdsch.PDSCHPrecoderBundle(spec);
end

function blocks = localTransportBlocks(raw, sizes, receiverOnly)
count = numel(sizes);
if receiverOnly
    if ~isempty(raw)
        error("sixgr:pdsch:CalibrationReceiverRejectsTransportBlockBits", ...
            ("Calibration RX does not accept transmitted transport-block " + ...
            "bits at its trust boundary."));
    end
    blocks = repmat({int8(zeros(0,1))},1,count);
    return;
end
if isempty(raw)
    blocks = cell(1,count);
    for cw = 1:count
        blocks{cw} = int8(randi([0 1], sizes(cw), 1));
    end
elseif iscell(raw)
    blocks = reshape(raw,1,[]);
else
    blocks = {raw};
end
if numel(blocks) ~= count
    error("sixgr:pdsch:DLSCHEncoder:CodewordCountMismatch", ...
        "Calibration requires one transport block per codeword.");
end
for cw = 1:count
    bits = double(blocks{cw}(:));
    if numel(bits) ~= sizes(cw) ...
            || any(~isfinite(bits) | (bits ~= 0 & bits ~= 1))
        error("sixgr:pdsch:DLSCHEncoder:TransportBlockSizeMismatch", ...
            "Calibration transport block %d differs from TBS=%d.", ...
            cw - 1, sizes(cw));
    end
    blocks{cw} = int8(bits);
end
end

function receiver = localReceiverConfig(cfg, request, tbs, ...
        nPhysicalPorts, legacyPrecoder, carrier, referenceConfig)
model = localReceiverChannelModel(cfg);
if logical(sixgr.util.structGet(cfg, "channel.awgnOnly", false))
    model = "AWGN";
end
nRx = double(request.NPhysicalRxAntennas);
if ~(isscalar(nRx) && isfinite(nRx) && nRx == fix(nRx) && nRx >= 1)
    nRx = nPhysicalPorts;
end
if model == "AWGN" && (nPhysicalPorts > 1 || nRx > 1 ...
        || double(legacyPrecoder.NumPRG) > 1)
    model = "STATIC-MIMO";
end
noiseVariance = localGridNoiseVariance( ...
    request.NoiseVariance, request.NoiseVarianceDomain, ...
    carrier, referenceConfig.get("OFDMOptions"));
receiver = struct( ...
    "TransportBlockSizes", double(tbs), ...
    "ChannelModel", char(model), ...
    "MaxIterations", double(request.MaxIterations), ...
    "Algorithm", char(string(request.Algorithm)), ...
    "LLRConvention", "positive_favours_bit_zero", ...
    "NPhysicalRxAntennas", nRx, ...
    "UseExactFlatPRGEstimator", logical(sixgr.util.structGet(cfg, ...
        "phy.pdsch.dmrs.useExactFlatStaticMIMOPRGEstimator", ...
        sixgr.util.structGet(cfg, ...
            "phy.pdsch.dmrs.useExactAWGNPRGEstimator", false))));
if ~isempty(noiseVariance)
    receiver.NoiseVariance = double(noiseVariance);
end
end

function model = localReceiverChannelModel(cfg)
% The receiver consumes an executable small-scale waveform profile, not
% the large-scale propagation authority.  In particular, TR38901 and ray
% tracing configurations must carry their explicitly configured concrete
% TDL/CDL profile through the immutable transmitter/receiver bundle.  Use
% the same fail-closed resolver as the system replay path so the bundle
% cannot silently reintroduce the broad channel-family token.
model = upper(strtrim(string(sixgr.channel.resolveConcreteProfile(cfg))));
end

function value = localGridNoiseVariance(raw, domain, carrier, ofdmOptions)
if isempty(raw)
    value = [];
    return;
end
domain = lower(strtrim(string(domain)));
if any(domain == ["grid","frequency"])
    value = double(raw);
    return;
end
calibration = sixgr.phy.waveform.calibrateOFDMNoiseTransform( ...
    carrier, ofdmOptions{:});
[value, ~] = sixgr.phy.waveform.convertNoiseVarianceToGridDomain( ...
    raw, calibration, "InputDomain", domain, ...
    "Source", "pdsch_calibration_facade");
end
