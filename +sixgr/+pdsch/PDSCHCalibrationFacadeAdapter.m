function [value, source] = localFirstPresent(valueStruct, paths)
value = [];
source = "";
for idx = 1:numel(paths)
    [candidate, present] = localGetPath(valueStruct, paths(idx));
    if present && ~isempty(candidate)
        value = candidate;
        source = paths(idx);
        return;
    end
end
end

function [value, present] = localGetPath(valueStruct, path)
parts = split(string(path), ".");
value = valueStruct;
present = true;
for idx = 1:numel(parts)
    name = char(parts(idx));
    if ~isstruct(value) || ~isscalar(value) || ~isfield(value,name)
        value = [];
        present = false;
        return;
    end
    value = value.(name);
end
end

function request = localValidateRequest(request)
required = ["TargetCodeRate","RV","XOverhead", ...
    "MCSTablePerCodeword","MCSIndexPerCodeword", ...
    "UECapability1024QAM","RRCEnabled1024QAM", ...
    "DCIEnabled1024QAM","DCIFormat","DeploymentAllows1024QAM", ...
    "UECapability1024QAMVariant","MaxNumberMIMOLayersPDSCH", ...
    "NumLayers", ...
    "FrequencyRange","OperatingBand","DeploymentClass", ...
    "FrequencyRangeAllows1024QAM","BandAllows1024QAM", ...
    "TransportBlockSizes","TransportBlockBits","CodingPlans", ...
    "PrecodingMatrix", ...
    "ReservedREZeroBased","DMRSAmplitudeScale", ...
    "DMRSPortResolutionPolicy", ...
    "NPhysicalRxAntennas","NoiseVariance","NoiseVarianceDomain", ...
    "MaxIterations","Algorithm"];
missing = required(~isfield(request, required));
if ~isempty(missing)
    error("sixgr:pdsch:IncompleteCalibrationFacadeRequest", ...
        "Calibration façade request is missing: %s.", ...
        strjoin(cellstr(missing), ", "));
end
if ~isfield(request, "ExecutionProfile")
    request.ExecutionProfile = "phy_calibration";
end
request.ExecutionProfile = lower(strtrim(string(request.ExecutionProfile)));
if ~any(request.ExecutionProfile == ["phy_calibration","scheduler_truth"])
    error("sixgr:pdsch:InvalidExplicitGrantAdapterProfile", ...
        "Explicit grant adapter profile '%s' is unsupported.", ...
        request.ExecutionProfile);
end
if ~isfield(request, "SchedulerGrantContext")
    request.SchedulerGrantContext = struct();
end
if request.ExecutionProfile == "scheduler_truth" && ...
        ~(isstruct(request.SchedulerGrantContext) && ...
        ~isempty(fieldnames(request.SchedulerGrantContext)))
    error("sixgr:pdsch:MissingSchedulerTruthGrantContext", ...
        "scheduler_truth materialization requires the decoded scheduler grant context.");
end
capabilityFields = [ ...
    "UECapability1024QAM","RRCEnabled1024QAM", ...
    "DCIEnabled1024QAM","DeploymentAllows1024QAM", ...
    "FrequencyRangeAllows1024QAM","BandAllows1024QAM"];
for idx = 1:numel(capabilityFields)
    name = capabilityFields(idx);
    if ~(islogical(request.(name)) && isscalar(request.(name)))
        error("sixgr:pdsch:Incomplete1024QAMCapabilityContext", ...
            "%s must be present as an explicit logical scalar.", name);
    end
end
textFields = ["FrequencyRange","OperatingBand","DeploymentClass","DCIFormat"];
for idx = 1:numel(textFields)
    name = textFields(idx);
    value = string(request.(name));
    if ~isscalar(value)
        error("sixgr:pdsch:Invalid1024QAMDeploymentContext", ...
            "%s must be an explicit string scalar.", name);
    end
    request.(name) = value;
end
variant = string(request.UECapability1024QAMVariant);
if ~isscalar(variant)
    error("sixgr:pdsch:Invalid1024QAMCapabilityVariant", ...
        "UECapability1024QAMVariant must be a string scalar.");
end
request.UECapability1024QAMVariant = variant;
maxLayers = double(request.MaxNumberMIMOLayersPDSCH);
if ~(isscalar(maxLayers) && (isnan(maxLayers) ...
        || (isfinite(maxLayers) && maxLayers == fix(maxLayers) ...
        && maxLayers >= 1)))
    error("sixgr:pdsch:Invalid1024QAMMaxNumberMIMOLayersPDSCH", ...
        "MaxNumberMIMOLayersPDSCH must be NaN or a positive integer.");
end
request.MaxNumberMIMOLayersPDSCH = maxLayers;
numLayers = double(request.NumLayers);
if ~(isscalar(numLayers) && isfinite(numLayers) ...
        && numLayers == fix(numLayers) ...
        && numLayers >= 1 && numLayers <= 8)
    error("sixgr:pdsch:InvalidCalibrationNumLayers", ...
        "Calibration NumLayers must be an integer from 1 through 8.");
end
request.NumLayers = numLayers;
if ~isfield(request, "ReceiverOnly")
    request.ReceiverOnly = false;
end
scale = double(request.DMRSAmplitudeScale);
if ~(isscalar(scale) && isfinite(scale) && scale > 0)
    error("sixgr:phy:dl:PDSCHDMRSEPREDifferenceInvalid", ...
        "DM-RS calibration amplitude scale must be finite and positive.");
end
end

function [modulation, layerCount] = localCodewordGeometry(pdsch)
nLayers = double(pdsch.NumLayers);
if ~(isscalar(nLayers) && isfinite(nLayers) ...
        && nLayers == fix(nLayers) && nLayers >= 1 && nLayers <= 8)
    error("sixgr:phy:dl:PDSCHCodewordLayerScope", ...
        "PDSCH supports ranks 1-8 in this calibration path.");
end
if nLayers <= 4
    layerCount = nLayers;
else
    splits = {[2 3], [3 3], [3 4], [4 4]};
    layerCount = splits{nLayers - 4};
end
modulation = string(pdsch.Modulation);
modulation = upper(strrep(strtrim(modulation(:).'), " ", ""));
if numel(modulation) ~= numel(layerCount)
    error("sixgr:phy:dl:PDSCHMissingCodewordSpecificModulation", ...
        "Calibration requires one modulation token per codeword.");
end
supported = ["QPSK","16QAM","64QAM","256QAM","1024QAM"];
if any(~ismember(modulation, supported))
    error("sixgr:pdsch:UnsupportedNRModulation", ...
        "Calibration contains an unsupported PDSCH modulation.");
end
end

