classdef PDSCHSchedulingAssignment
    %PDSCHSchedulingAssignment Immutable, zero-based PDSCH scheduling truth.
    %
    % The object owns explicitly transmitter-scheduled or receiver-decoded
    % state. A transmitter-owned instance never authorizes reception.
    % Configuration structs are
    % never accepted as a substitute for this object by connected_strict or
    % sps_strict execution.

    properties (SetAccess = immutable)
        Data (1,1) struct
        AssignmentId (1,1) string
        Profile (1,1) string
        Source (1,1) string
        ExecutionValidationDigest (1,1) string
    end

    methods
        function obj = PDSCHSchedulingAssignment(data)
            arguments
                data (1,1) struct
            end

            required = sixgr.pdsch.PDSCHSchedulingAssignment.requiredFields();
            missing = required(~isfield(data, required));
            if ~isempty(missing)
                error("sixgr:pdsch:IncompleteSchedulingAssignment", ...
                    "PDSCH scheduling assignment is missing required field(s): %s.", ...
                    strjoin(cellstr(missing), ", "));
            end

            profile = lower(strtrim(string(data.Profile)));
            if ~any(profile == ["connected_strict","sps_strict","ra_si_strict","scheduler_truth","phy_calibration"])
                error("sixgr:pdsch:UnsupportedExecutionProfile", ...
                    "Unsupported PDSCH execution profile '%s'.", profile);
            end
            source = string(data.Source);
            if strlength(strtrim(source)) == 0
                error("sixgr:pdsch:MissingAssignmentSource", ...
                    "PDSCH scheduling assignment Source must be nonempty.");
            end
            assignmentId = string(data.AssignmentId);
            if strlength(strtrim(assignmentId)) == 0
                error("sixgr:pdsch:MissingAssignmentId", ...
                    "PDSCH scheduling assignment AssignmentId must be nonempty.");
            end
            sixgr.pdsch.PDSCHSchedulingAssignment.validateData(data);

            obj.Data = orderfields(data);
            obj.AssignmentId = assignmentId;
            obj.Profile = profile;
            obj.Source = source;
            obj.ExecutionValidationDigest = ...
                sixgr.pdsch.PDSCHSchedulingAssignment.digest(obj.Data);
        end

        function value = get(obj, name)
            name = char(string(name));
            if ~isfield(obj.Data, name)
                error("sixgr:pdsch:UnknownAssignmentField", ...
                    "PDSCH scheduling assignment has no field '%s'.", name);
            end
            value = obj.Data.(name);
        end

        function data = toStruct(obj)
            data = obj.Data;
        end

        function digest = validateForExecution(obj)
            %VALIDATEFOREXECUTION Recheck the complete immutable PHY contract.
            %
            % Canonical TX/RX call this method at their trust boundary.  It
            % prevents an object with only the right class name/profile token
            % from bypassing DCI/SPS/calibration and per-codeword invariants.
            sixgr.pdsch.PDSCHSchedulingAssignment.validateData(obj.Data);
            digest = sixgr.pdsch.PDSCHSchedulingAssignment.digest(obj.Data);
            if digest ~= obj.ExecutionValidationDigest
                error("sixgr:pdsch:SchedulingAssignmentDigestMismatch", ...
                    "Immutable PDSCH scheduling-assignment data changed after validation.");
            end
        end
    end

    methods (Static)
        function fields = requiredFields()
            fields = [ ...
                "AssignmentId","Profile","UEId","RNTI","RNTIType", ...
                "ServingCellId","SchedulingCellId","CCId","BWPId", ...
                "ConfigurationEpoch","PDCCHAbsoluteSlot","PDSCHAbsoluteSlot", ...
                "DecodedDCIId","ScheduledDCIId","ControlAuthority", ...
                "DCIFormat","DCICRCPass","DecodedRNTI", ...
                "DCIRNTIMatch","SearchSpaceId","CORESETId","FDRAType", ...
                "FrequencyDomainAssignmentRaw","RBGSize","VRBToPRBMapping", ...
                "InterleaverBundleSize","PRBSetBWPRelative", ...
                "PRBSetCarrierRelative","TDRAListId","TDRARowIndex","K0", ...
                "SLIV","SymbolAllocation","MappingType","MCSTablePerCodeword", ...
                "MCSIndexPerCodeword","ModulationPerCodeword","QmPerCodeword", ...
                "TargetCodeRatePerCodeword","TBScalingPerCodeword","XOverhead", ...
                "NumLayers","NumCodewords","LayerCountPerCodeword", ...
                "AntennaPortField","DMRSConfigId","DMRSPortSet","PTRSConfigId", ...
                "PTRSPortSet","NDIPerCodeword","RVPerCodeword","HARQProcessId", ...
                "DAI","TCIStateId","RateMatchPatternIds","ZPCSIRSResourceIds", ...
                "TransmissionConfigurationIndication","SPSConfigId", ...
                "SPSActivationDCIId","SPSActivationDCICRCPass", ...
                "SPSActivationDCIRNTIMatch","SPSConfigurationEpoch", ...
                "SPSActivated","SPSReleased","SPSOccasionIndex","Source"];
            fields = [fields, ...
                "UECapability1024QAM","RRCEnabled1024QAM", ...
                "UECapability1024QAMVariant", ...
                "MaxNumberMIMOLayersPDSCH", ...
                "DCIEnabled1024QAM","DeploymentAllows1024QAM", ...
                "FrequencyRange","OperatingBand","DeploymentClass", ...
                "FrequencyRangeAllows1024QAM", ...
                "BandAllows1024QAM"];
        end
    end

    methods (Static, Access = private)
        function validateData(data)
            if isfield(data,'DefaultCORESETQCLReference')
                sixgr.pdsch.CORESETQCLReference.validate(data.DefaultCORESETQCLReference,data);
            end
            profile = lower(strtrim(string(data.Profile)));
            source = string(data.Source);
            nLayers = sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                data.NumLayers, "NumLayers", 1, 8);
            nCodewords = sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                data.NumCodewords, "NumCodewords", 1, 2);
            expectedCodewords = 1 + double(nLayers > 4);
            if nCodewords ~= expectedCodewords
                error("sixgr:pdsch:CodewordLayerMismatch", ...
                    "PDSCH rank %d requires NumCodewords=%d.", ...
                    nLayers, expectedCodewords);
            end

            layerCounts = sixgr.pdsch.PDSCHSchedulingAssignment.numericVector( ...
                data.LayerCountPerCodeword, nCodewords, ...
                "LayerCountPerCodeword");
            if any(layerCounts < 1 | layerCounts ~= fix(layerCounts)) ...
                    || sum(layerCounts) ~= nLayers
                error("sixgr:pdsch:CodewordLayerMismatch", ...
                    "LayerCountPerCodeword must be positive integers summing to NumLayers.");
            end
            expectedLayers = {1,2,3,4,[2 3],[3 3],[3 4],[4 4]};
            if ~isequal(layerCounts, double(expectedLayers{nLayers}))
                error("sixgr:pdsch:CodewordLayerMismatch", ...
                    "Rank-%d codeword-to-layer split is invalid.", nLayers);
            end

            tables = sixgr.pdsch.PDSCHSchedulingAssignment.stringVector( ...
                data.MCSTablePerCodeword, nCodewords, ...
                "MCSTablePerCodeword");
            indices = sixgr.pdsch.PDSCHSchedulingAssignment.numericVector( ...
                data.MCSIndexPerCodeword, nCodewords, ...
                "MCSIndexPerCodeword");
            modulation = upper(sixgr.pdsch.PDSCHSchedulingAssignment.stringVector( ...
                data.ModulationPerCodeword, nCodewords, ...
                "ModulationPerCodeword"));
            qm = sixgr.pdsch.PDSCHSchedulingAssignment.numericVector( ...
                data.QmPerCodeword, nCodewords, "QmPerCodeword");
            rates = sixgr.pdsch.PDSCHSchedulingAssignment.numericVector( ...
                data.TargetCodeRatePerCodeword, nCodewords, ...
                "TargetCodeRatePerCodeword");
            tbScaling = sixgr.pdsch.PDSCHSchedulingAssignment.numericVector( ...
                data.TBScalingPerCodeword, nCodewords, ...
                "TBScalingPerCodeword");
            ndi = sixgr.pdsch.PDSCHSchedulingAssignment.numericVector( ...
                data.NDIPerCodeword, nCodewords, "NDIPerCodeword");
            rv = sixgr.pdsch.PDSCHSchedulingAssignment.numericVector( ...
                data.RVPerCodeword, nCodewords, "RVPerCodeword");
            if any(indices ~= fix(indices) | indices < 0) ...
                    || any(rv ~= fix(rv) | rv < 0 | rv > 3) ...
                    || any(ndi ~= fix(ndi) | ~ismember(ndi, [0 1])) ...
                    || any(~ismember(tbScaling, [0.25 0.5 1]))
                error("sixgr:pdsch:InvalidCodewordState", ...
                    ["MCS, NDI, RV, and TB-scaling values must be explicit " ...
                    "valid per-codeword state."]);
            end

            capabilityNames = [ ...
                "UECapability1024QAM","RRCEnabled1024QAM", ...
                "DCIEnabled1024QAM","DeploymentAllows1024QAM", ...
                "FrequencyRangeAllows1024QAM", ...
                "BandAllows1024QAM"];
            deploymentNames = [ ...
                "FrequencyRange","OperatingBand","DeploymentClass"];
            for idx = 1:numel(deploymentNames)
                name = deploymentNames(idx);
                value = string(data.(name));
                if ~isscalar(value) || strlength(strtrim(value)) == 0
                    error("sixgr:pdsch:Invalid1024QAMDeploymentContext", ...
                        "%s must be an explicit nonempty string scalar.", ...
                        name);
                end
            end
            mcsContext = struct( ...
                "NumCodewords", nCodewords, ...
                "RNTIType", string(data.RNTIType), ...
                "SelectionSource", source, ...
                "ExecutionProfile", profile, ...
                "CalibrationTokenPerCodeword", tables, ...
                "CalibrationModulationPerCodeword", modulation, ...
                "CalibrationQmPerCodeword", qm, ...
                "CalibrationTargetCodeRatePerCodeword", rates, ...
                "DCIFormat", string(data.DCIFormat), ...
                "NumLayers", nLayers, ...
                "UECapability1024QAMVariant", ...
                    string(data.UECapability1024QAMVariant), ...
                "MaxNumberMIMOLayersPDSCH", ...
                    data.MaxNumberMIMOLayersPDSCH, ...
                "FrequencyRange", string(data.FrequencyRange), ...
                "OperatingBand", string(data.OperatingBand), ...
                "DeploymentClass", string(data.DeploymentClass), ...
                "FrequencyRangeAllows1024QAM", ...
                    data.FrequencyRangeAllows1024QAM, ...
                "BandAllows1024QAM", data.BandAllows1024QAM);
            for idx = 1:numel(capabilityNames)
                name = capabilityNames(idx);
                value = data.(name);
                if ~(islogical(value) && isscalar(value))
                    error("sixgr:pdsch:Invalid1024QAMCapabilityContext", ...
                        "%s must be an explicit logical scalar.", name);
                end
                mcsContext.(name) = logical(value);
            end
            if isfield(data,'ReceivedHARQCodingHistory')
                history=data.ReceivedHARQCodingHistory;
                assert(isa(history,'sixgr.pdsch.ReceivedDLHARQCodingHistory'), ...
                    'sixgr:pdsch:ReceivedDLHARQHistoryRequired', ...
                    'Retained coding metadata must be an immutable UE received-control history.');
                profiles=history.validateAssignmentData(data);
            else
                profiles = sixgr.pdsch.PDSCHMCSResolver.resolve( ...
                    tables, indices, mcsContext);
            end
            for cw = 1:nCodewords
                if modulation(cw) ~= upper(string(profiles(cw).Modulation)) ...
                        || qm(cw) ~= double(profiles(cw).Qm) ...
                        || abs(rates(cw) - double(profiles(cw).TargetCodeRate)) > 1e-12
                    error("sixgr:pdsch:MCSAssignmentMismatch", ...
                        ['Codeword %d MCS table/index resolves to %s/Qm=%g/R=%.15g, ' ...
                        'not %s/Qm=%g/R=%.15g.'], cw - 1, ...
                        char(string(profiles(cw).Modulation)), profiles(cw).Qm, ...
                        profiles(cw).TargetCodeRate, char(modulation(cw)), ...
                        qm(cw), rates(cw));
                end
            end

            rnti = sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                data.RNTI, "RNTI", 0, 65535);
            decodedRNTI = double(data.DecodedRNTI);
            sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                data.ConfigurationEpoch, "ConfigurationEpoch", 0, flintmax);
            sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                data.PDSCHAbsoluteSlot, "PDSCHAbsoluteSlot", 0, flintmax);
            sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                data.CCId, "CCId", 0, flintmax);
            sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                data.BWPId, "BWPId", 0, flintmax);
            sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                data.HARQProcessId, "HARQProcessId", 0, 15);
            xOverhead = sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                data.XOverhead, "XOverhead", 0, 18);
            if ~ismember(xOverhead, [0 6 12 18])
                error("sixgr:pdsch:InvalidXOverhead", ...
                    "XOverhead must be one of 0, 6, 12, or 18 RE per PRB.");
            end

            bwpPRB = sixgr.pdsch.PDSCHSchedulingAssignment.prbVector( ...
                data.PRBSetBWPRelative, "PRBSetBWPRelative");
            carrierPRB = sixgr.pdsch.PDSCHSchedulingAssignment.prbVector( ...
                data.PRBSetCarrierRelative, "PRBSetCarrierRelative");
            if numel(bwpPRB) ~= numel(carrierPRB)
                error("sixgr:pdsch:PRBMappingLengthMismatch", ...
                    "BWP-relative and carrier-relative PRB sets must have equal length.");
            end
            symbols = sixgr.pdsch.PDSCHSchedulingAssignment.numericVector( ...
                data.SymbolAllocation, 2, "SymbolAllocation");
            if any(symbols ~= fix(symbols)) || symbols(1) < 0 ...
                    || symbols(2) < 1
                error("sixgr:pdsch:InvalidSymbolAllocation", ...
                    ["SymbolAllocation must be explicit zero-based " ...
                    "[start length]. The canonical carrier validates the " ...
                    "cyclic-prefix-dependent slot boundary at execution."]);
            end
            if ~any(upper(strtrim(string(data.MappingType))) == ["A","B"])
                error("sixgr:pdsch:InvalidMappingType", ...
                    "MappingType must be A or B.");
            end
            ports = sixgr.pdsch.PDSCHSchedulingAssignment.prbVector( ...
                data.DMRSPortSet, "DMRSPortSet");
            if numel(ports) ~= nLayers
                error("sixgr:pdsch:DMRSPortLayerCountMismatch", ...
                    "Exactly one explicit logical DM-RS port per PDSCH layer is required.");
            end
            if any(ports > 23)
                error("sixgr:pdsch:InvalidDMRSPortSet", ...
                    "Logical PDSCH DM-RS ports must lie in the Release-18 range 0...23.");
            end

            if profile == "connected_strict" || profile == "ra_si_strict" || ...
                    profile == "scheduler_truth"
                expectedSource = "decoded_dci+ue_context";
                if profile == "ra_si_strict"
                    expectedSource = "decoded_dci+procedure_context";
                elseif profile == "scheduler_truth"
                    expectedSource = "decoded_scheduler_grant+pdcch_binding";
                end
                receiverOwned = source == expectedSource ...
                    && strlength(strtrim(string(data.DecodedDCIId))) > 0 ...
                    && strlength(strtrim(string(data.ScheduledDCIId))) == 0 ...
                    && string(data.ControlAuthority) == "receiver_crc_valid_decode" ...
                    && isequal(data.DCICRCPass, true) ...
                    && isequal(data.DCIRNTIMatch, true) ...
                    && isscalar(decodedRNTI) && isfinite(decodedRNTI) ...
                    && decodedRNTI == rnti;
                transmitterSource = (profile == "ra_si_strict" ...
                    && source == "scheduled_dci+procedure_context") ...
                    || (profile == "connected_strict" ...
                    && source == "scheduled_dci+ue_context") ...
                    || (profile == "scheduler_truth" ...
                    && source == "scheduled_scheduler_grant+authored_dci");
                transmitterOwned = transmitterSource ...
                    && strlength(strtrim(string(data.ScheduledDCIId))) > 0 ...
                    && strlength(strtrim(string(data.DecodedDCIId))) == 0 ...
                    && string(data.ControlAuthority) == "transmitter_scheduled_dci" ...
                    && isequal(data.DCICRCPass, false) ...
                    && isequal(data.DCIRNTIMatch, false) ...
                    && isscalar(decodedRNTI) && isnan(decodedRNTI);
                if ~(receiverOwned || transmitterOwned)
                    error("sixgr:pdsch:UnvalidatedDecodedDCIAssignment", ...
                        "Strict procedure assignment must have either transmitter " + ...
                        "scheduled-DCI ownership or receiver CRC-valid decoded-DCI ownership.");
                end
                pdcchSlot = sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                    data.PDCCHAbsoluteSlot, "PDCCHAbsoluteSlot", 0, flintmax);
                k0 = sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                    data.K0, "K0", 0, flintmax);
                if pdcchSlot + k0 ~= double(data.PDSCHAbsoluteSlot)
                    error("sixgr:pdsch:AssignmentSlotBindingMismatch", ...
                        "PDCCHAbsoluteSlot + K0 must equal PDSCHAbsoluteSlot.");
                end
                rntiType = upper(strtrim(string(data.RNTIType)));
                if profile == "connected_strict" || profile == "scheduler_truth"
                    allowed = ["C-RNTI","CS-RNTI","MCS-C-RNTI"];
                else
                    allowed = ["SI-RNTI","P-RNTI","RA-RNTI","TC-RNTI"];
                end
                if ~any(rntiType == allowed)
                    error("sixgr:pdsch:InvalidDCIRNTIProcedure", ...
                        "RNTI type '%s' is invalid for profile '%s'.", ...
                        rntiType, profile);
                end
            elseif profile == "sps_strict"
                if source ~= "sps_activation_dci+rrc_context" ...
                        || strlength(strtrim(string(data.SPSConfigId))) == 0 ...
                        || strlength(strtrim(string(data.SPSActivationDCIId))) == 0 ...
                        || ~isequal(data.SPSActivationDCICRCPass, true) ...
                        || ~isequal(data.SPSActivationDCIRNTIMatch, true) ...
                        || ~isequal(data.SPSActivated, true) ...
                        || ~isequal(data.SPSReleased, false) ...
                        || double(data.SPSConfigurationEpoch) ~= ...
                            double(data.ConfigurationEpoch)
                    error("sixgr:pdsch:UnvalidatedSPSAssignment", ...
                        "SPS assignment lacks an active epoch-matched activation-DCI context.");
                end
                sixgr.pdsch.PDSCHSchedulingAssignment.integerScalar( ...
                    data.SPSOccasionIndex, "SPSOccasionIndex", 0, flintmax);
            elseif profile == "phy_calibration"
                if source ~= "calibration_assignment" ...
                        || strlength(strtrim(string(data.DecodedDCIId))) ~= 0 ...
                        || ~isequal(data.DCICRCPass, false) ...
                        || ~isequal(data.DCIRNTIMatch, false)
                    error("sixgr:pdsch:InvalidCalibrationAssignment", ...
                        "Calibration assignments must be isolated from decoded-DCI ownership.");
                end
            end
        end

        function value = integerScalar(value, name, minimum, maximum)
            value = double(value);
            if ~(isscalar(value) && isfinite(value) && value == fix(value) ...
                    && value >= minimum && value <= maximum)
                error("sixgr:pdsch:InvalidAssignmentInteger", ...
                    "%s must be an integer in [%g,%g].", ...
                    char(string(name)), minimum, maximum);
            end
        end

        function value = numericVector(value, count, name)
            if ~(isnumeric(value) || islogical(value))
                error("sixgr:pdsch:MissingCodewordSpecificAssignmentValue", ...
                    "%s must be numeric.", char(string(name)));
            end
            value = double(value(:).');
            if numel(value) ~= count || any(~isfinite(value))
                error("sixgr:pdsch:MissingCodewordSpecificAssignmentValue", ...
                    "%s must contain exactly %d finite value(s).", ...
                    char(string(name)), count);
            end
        end

        function value = stringVector(value, count, name)
            value = string(value);
            value = value(:).';
            if numel(value) ~= count || any(strlength(strtrim(value)) == 0)
                error("sixgr:pdsch:MissingCodewordSpecificAssignmentValue", ...
                    "%s must contain exactly %d nonempty token(s).", ...
                    char(string(name)), count);
            end
        end

        function value = prbVector(value, name)
            value = double(value(:).');
            if isempty(value) || any(~isfinite(value) | value ~= fix(value) ...
                    | value < 0) || numel(unique(value)) ~= numel(value)
                error("sixgr:pdsch:InvalidAssignmentIndexSet", ...
                    "%s must be a nonempty unique nonnegative-integer vector.", ...
                    char(string(name)));
            end
        end

        function value = digest(data)
            bytes = uint8(unicode2native( ...
                jsonencode(orderfields(data)), "UTF-8"));
            value = string(sixgr.util.sha256Hex(bytes));
        end
    end
