function [carrier, info] = CarrierConfig6GR(cfg, varargin)
%CarrierConfig6GR Build the carrier used by the 6GR PDSCH truth study.

carrierCfg = struct();
carrierCfg.phy = struct();
cellId = double(sixgr.util.structGet(cfg, "CellID", sixgr.util.structGet(cfg, "phy.carrier.NCellID", 1)));
mu = double(sixgr.util.structGet(cfg, "Numerology", sixgr.util.structGet(cfg, "phy.numerology.mu", 1)));
nSizeGrid = double(sixgr.util.structGet(cfg, "NSizeGrid", sixgr.util.structGet(cfg, "phy.carrier.NSizeGrid", 52)));
slotNumber = double(sixgr.util.structGet(cfg, "SlotNumber", sixgr.util.structGet(cfg, "phy.carrier.NSlot", 0)));
frameNumber = double(sixgr.util.structGet(cfg, "FrameNumber", sixgr.util.structGet(cfg, "phy.carrier.NFrame", 0)));
carrierCfg.phy.carrier = struct( ...
    "NCellID", cellId, ...
    "SubcarrierSpacing", double(15 * 2^mu), ...
    "NSizeGrid", nSizeGrid, ...
    "NStartGrid", 0, ...
    "NSlot", slotNumber, ...
    "NFrame", frameNumber, ...
    "CyclicPrefix", "normal");
[carrier, info] = sixgr.phy.grid.makeCarrier(carrierCfg, varargin{:});
end
