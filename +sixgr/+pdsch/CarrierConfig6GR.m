function [carrier, info] = CarrierConfig6GR(cfg, varargin)
%CarrierConfig6GR Build the carrier used by the 6GR PDSCH truth study.

carrierCfg = struct();
carrierCfg.phy = struct();
cellId = double(sixgr.util.structGet(cfg, "CellID", sixgr.util.structGet(cfg, "phy.carrier.NCellID", 1)));
numerology = localResolveNumerology(cfg);
nSizeGrid = double(sixgr.util.structGet(cfg, "NSizeGrid", sixgr.util.structGet(cfg, "phy.carrier.NSizeGrid", 52)));
slotNumber = double(sixgr.util.structGet(cfg, "SlotNumber", sixgr.util.structGet(cfg, "phy.carrier.NSlot", 0)));
frameNumber = double(sixgr.util.structGet(cfg, "FrameNumber", sixgr.util.structGet(cfg, "phy.carrier.NFrame", 0)));
carrierCfg.phy.carrier = struct( ...
    "NCellID", cellId, ...
    "SubcarrierSpacing", double(numerology.SubcarrierSpacingKHz), ...
    "NSizeGrid", nSizeGrid, ...
    "NStartGrid", 0, ...
    "NSlot", slotNumber, ...
    "NFrame", frameNumber, ...
    "CyclicPrefix", char(string(numerology.CyclicPrefix)));
[carrier, info] = sixgr.phy.grid.makeCarrier(carrierCfg, varargin{:});
end

function numerology = localResolveNumerology(cfg)
mu = double(sixgr.util.structGet(cfg, ...
    "Numerology", sixgr.util.structGet(cfg, "phy.numerology.mu", NaN)));
scsKHz = double(sixgr.util.structGet(cfg, ...
    "SubcarrierSpacing_kHz", ...
    sixgr.util.structGet(cfg, "phy.carrier.SubcarrierSpacing", ...
    sixgr.util.structGet(cfg, "phy.carrier.SubcarrierSpacing_kHz", NaN))));
cp = string(sixgr.util.structGet(cfg, ...
    "CyclicPrefix", sixgr.util.structGet(cfg, ...
    "phy.carrier.CyclicPrefix", "normal")));
if isfinite(scsKHz)
    numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
        scsKHz, cp, "generic_waveform_test", "");
    if isfinite(mu) && mu ~= double(numerology.Mu)
        error("sixgr:pdsch:CarrierConfig6GR:NumerologyMismatch", ...
            "Configured mu=%g conflicts with SCS=%g kHz.", mu, scsKHz);
    end
    return;
end
base = sixgr.phy.frame.AbsoluteTime.resolveNumerology(mu);
numerology = sixgr.phy.frame.NumerologyCatalog.resolve( ...
    base.SCSKHz, cp, "generic_waveform_test", "");
end
