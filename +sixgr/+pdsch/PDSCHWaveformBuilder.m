function txBundle = PDSCHWaveformBuilder(cfg, fdraAlloc, tdraAlloc, amc, varargin)
%PDSCHWaveformBuilder Build truthful PDSCH waveform copies for one HARQ tx.

ip = inputParser;
ip.addParameter("QueueBits", cfg.QueueBits, @(x) isnumeric(x) && isscalar(x) && x >= 1);
ip.addParameter("RV", 0, @(x) isnumeric(x) && isscalar(x) && x >= 0);
ip.addParameter("TransmissionIndex", 1, @(x) isnumeric(x) && isscalar(x) && x >= 1);
ip.parse(varargin{:});
opt = ip.Results;

copies = tdraAlloc.CopyTable;

layerTrace = table();
copyBundles = cell(height(copies), 1);
queueFitStatus = "";
payloadBitsOriginal = [];
transportBlockSize = NaN;
transportBlockBits = [];

for i = 1:height(copies)
    slotNumber = cfg.SlotNumber + double(copies.SlotOffset(i)) + double(cfg.TDRA.SchedulingOffsetSlots);
    symbolAllocation = [double(copies.StartSymbol(i)) + double(cfg.TDRA.SchedulingOffsetSymbols), double(copies.NumSymbols(i))];
    runtimeCfg = localBuildRuntimeCfg(cfg, fdraAlloc, tdraAlloc, ...
        symbolAllocation, slotNumber, amc);
    [carrier, ~] = sixgr.pdsch.CarrierConfig6GR(runtimeCfg);
    pdsch = localBuildPDSCHConfig(runtimeCfg, carrier, amc, ...
        fdraAlloc, tdraAlloc, symbolAllocation);
    [pdsch, amc, payloadBitsOriginal, queueFitStatus, transportBlockSize] = localFitGrantToQueue(cfg, carrier, pdsch, amc, double(opt.QueueBits));
    runtimeCfg = localBindRuntimeGrant(runtimeCfg,pdsch,amc);
    if isempty(transportBlockBits)
        transportBlockBits = localMakeTransportBlocks(double(transportBlockSize), payloadBitsOriginal, cfg.Seed + double(opt.TransmissionIndex));
    elseif ~isequal(double(localTransportBlockSizes(transportBlockBits)), double(transportBlockSize(:).'))
        error("sixgr:pdsch:PDSCHWaveformBuilder:RepetitionTBSMismatch", ...
            "PDSCH repetition copies must carry the same per-codeword transport block size. First copy TBS=%s, copy %d TBS=%s.", ...
            mat2str(localTransportBlockSizes(transportBlockBits)), i, mat2str(double(transportBlockSize(:).')));
    end
    tbBits = transportBlockBits;
    targetCodeRatePerCodeword = localStudyPerCodewordValue( ...
        amc.TargetCodeRate, pdsch.NumLayers, "TargetCodeRate");
    rvPerCodeword = localStudyPerCodewordValue( ...
        double(opt.RV), pdsch.NumLayers, "RV");
    [tx, txInfo] = sixgr.phy.dl.PDSCH_Tx(runtimeCfg, ...
        "Carrier", carrier, ...
        "PDSCH", pdsch, ...
        "TransportBlockBits", tbBits, ...
        "TargetCodeRate", targetCodeRatePerCodeword, ...
        "RV", rvPerCodeword, ...
        "ExecutionProfile", "phy_calibration");
    tx = localApplyWidebandPhaseErrors(tx, cfg, i);
    encoderEvidence = localExactDLSCHEncodeEvidence(tx);
    scramblingEvidence = localExactScramblingEvidence(tx);
    modulationEvidence = localExactModulationEvidence(tx);
    copyLayerTrace = localExactLayerMappingTrace(tx);
    if isempty(layerTrace)
        layerTrace = copyLayerTrace;
    elseif ~isequal(layerTrace, copyLayerTrace)
        error("sixgr:pdsch:PDSCHWaveformBuilder:RepetitionLayerMappingMismatch", ...
            "PDSCH repetition copies changed the exact canonical layer-mapping trace.");
    end
    [dmrs, dmrsT] = sixgr.pdsch.PDSCHDMRS(carrier, pdsch);
    [ptrs, ptrsT] = sixgr.pdsch.PDSCHPTRS(carrier, pdsch);
    copyBundles{i} = struct( ...
        "Tx", tx, ...
        "TxInfo", txInfo, ...
        "RuntimeCfg", runtimeCfg, ...
        "Carrier", carrier, ...
        "PDSCH", pdsch, ...
        "FDRA", fdraAlloc, ...
        "TDRA", struct("SlotNumber", slotNumber, "SymbolAllocation", symbolAllocation), ...
        "DMRS", dmrs, ...
        "DMRSTable", dmrsT, ...
        "PTRS", ptrs, ...
        "PTRSTable", ptrsT, ...
        "LayerMappingTrace", copyLayerTrace, ...
        "ScramblingMeta", scramblingEvidence, ...
        "ModulationMeta", modulationEvidence, ...
        "EncoderMeta", encoderEvidence, ...
        "GridMap", sixgr.pdsch.PDSCHGridMapper(tx), ...
        "ExecutionProfile", "phy_calibration", ...
        "StrictSchedulingOwnership", false, ...
        "SchedulingOwnership", "study_calibration_scheduler", ...
        "QueueFitStatus", queueFitStatus, ...
        "PayloadBitsBeforePadding", double(localPayloadBitCount(payloadBitsOriginal)), ...
        "TransportBlockSize", double(transportBlockSize), ...
        "TransportBlockBits", {tbBits});
end

txBundle = struct();
txBundle.Copies = copyBundles;
txBundle.ActiveAMC = amc;
txBundle.FDRA = fdraAlloc;
txBundle.TDRA = tdraAlloc;
txBundle.LayerMappingTrace = layerTrace;
txBundle.QueueFitStatus = char(queueFitStatus);
txBundle.PayloadBitsBeforePadding = double(localPayloadBitCount(payloadBitsOriginal));
txBundle.RV = double(opt.RV);
txBundle.RepetitionMode = char(cfg.RepetitionMode);
txBundle.RepetitionCount = height(copies);
txBundle.TransportBlockSize = double(copyBundles{1}.TransportBlockSize(:).');
txBundle.TransportBlockBits = copyBundles{1}.TransportBlockBits;
end

function runtimeCfg = localBindRuntimeGrant(runtimeCfg,pdsch,amc)
% Bind the immutable calibration request to the post-queue-fit grant.
nCodewords = localPDSCHCodewordCount(double(pdsch.NumLayers));
runtimeCfg.phy.pdsch.modulation = ...
    localModulationForCodewords(amc.Modulation,pdsch.NumLayers);
runtimeCfg.phy.pdsch.prbSet = double(pdsch.PRBSet(:).');
runtimeCfg.phy.pdsch.codeRate = localStudyPerCodewordValue( ...
    amc.TargetCodeRate,pdsch.NumLayers,"TargetCodeRate");
runtimeCfg.phy.pdsch.mcsTable = ...
    repmat(string(amc.MCSTable),1,nCodewords);
runtimeCfg.phy.pdsch.mcsIndex = ...
    repmat(double(amc.MCSIndex),1,nCodewords);
end

function evidence = localExactDLSCHEncodeEvidence(tx)
if ~isstruct(tx) || ~isfield(tx, "DLSCHEncode") ...
        || ~isfield(tx, "CodingPlans")
    error("sixgr:pdsch:PDSCHWaveformBuilder:MissingDLSCHCodingEvidence", ...
        "Canonical PDSCH TX must expose DLSCHEncode and immutable CodingPlans.");
end
plans = localExactCodingPlans(tx);
planIDs = string(cellfun(@(plan) plan.PlanID, plans, ...
    "UniformOutput", false));
layoutHashes = string(cellfun(@(plan) plan.CodingLayoutHash, plans, ...
    "UniformOutput", false));
evidence = tx.DLSCHEncode;
if numel(plans) == 1
    encodedIDs = string(sixgr.util.structGet( ...
        evidence, "CodingPlanID", ""));
else
    encodedIDs = string(sixgr.util.structGet( ...
        evidence, "CodingPlanIDs", strings(1,0)));
end
encodedIDs = reshape(encodedIDs, 1, []);
if ~isequal(encodedIDs, planIDs)
    error("sixgr:pdsch:PDSCHWaveformBuilder:DLSCHCodingPlanMismatch", ...
        "Canonical DLSCHEncode plan IDs do not match the exact TX CodingPlans.");
end
evidence.CodingPlanIdentityVerified = true;
evidence.CodingPlanIDs = planIDs;
evidence.CodingLayoutHashes = layoutHashes;
evidence.MetadataSource = ...
    "canonical_explicit_dlsch_encode_with_immutable_plans";
end

function evidence = localExactScramblingEvidence(tx)
plans = localExactCodingPlans(tx);
if ~isfield(tx, "ScramblingInfo") || ~iscell(tx.ScramblingInfo) ...
        || numel(tx.ScramblingInfo) ~= numel(plans)
    error("sixgr:pdsch:PDSCHWaveformBuilder:MissingScramblingEvidence", ...
        "Canonical PDSCH TX must expose one exact ScramblingInfo per coding plan.");
end
codewords = cell(1, numel(plans));
for cw = 1:numel(plans)
    info = tx.ScramblingInfo{cw};
    plan = plans{cw};
    if ~isstruct(info) ...
            || double(sixgr.util.structGet( ...
                info, "CodewordIndex", NaN)) ~= double(plan.CodewordIndex) ...
            || double(sixgr.util.structGet( ...
                info, "Length", NaN)) ~= double(plan.RateMatchedBitCount)
        error("sixgr:pdsch:PDSCHWaveformBuilder:ScramblingPlanMismatch", ...
            "Canonical scrambling evidence for codeword %d does not match its immutable coding plan.", ...
            cw - 1);
    end
    info.CodingPlanID = plan.PlanID;
    info.CodingLayoutHash = plan.CodingLayoutHash;
    info.Source = "canonical_explicit_pdsch_scrambling_transform";
    codewords{cw} = info;
end
evidence = struct( ...
    "ContractVersion", "ExactPDSCHScramblingEvidence/v1", ...
    "Codewords", {codewords}, ...
    "CodingPlanIDs", string(cellfun(@(plan) plan.PlanID, plans, ...
        "UniformOutput", false)), ...
    "Source", "canonical_tx_scrambling_info");
end

function evidence = localExactModulationEvidence(tx)
plans = localExactCodingPlans(tx);
if ~isfield(tx, "ModulationInfo") || ~iscell(tx.ModulationInfo) ...
        || numel(tx.ModulationInfo) ~= numel(plans)
    error("sixgr:pdsch:PDSCHWaveformBuilder:MissingModulationEvidence", ...
        "Canonical PDSCH TX must expose one exact ModulationInfo per coding plan.");
end
codewords = cell(1, numel(plans));
for cw = 1:numel(plans)
    info = tx.ModulationInfo{cw};
    plan = plans{cw};
    expectedSymbols = double(plan.RateMatchedBitCount) ...
        / double(plan.ModulationOrder);
    if ~isstruct(info) ...
            || upper(string(sixgr.util.structGet( ...
                info, "Modulation", ""))) ~= upper(string(plan.Modulation)) ...
            || double(sixgr.util.structGet( ...
                info, "Qm", NaN)) ~= double(plan.ModulationOrder) ...
            || double(sixgr.util.structGet( ...
                info, "InputCount", NaN)) ~= ...
                double(plan.RateMatchedBitCount) ...
            || double(sixgr.util.structGet( ...
                info, "OutputCount", NaN)) ~= expectedSymbols
        error("sixgr:pdsch:PDSCHWaveformBuilder:ModulationPlanMismatch", ...
            "Canonical modulation evidence for codeword %d does not match its immutable coding plan.", ...
            cw - 1);
    end
    info.CodingPlanID = plan.PlanID;
    info.CodingLayoutHash = plan.CodingLayoutHash;
    info.Source = "canonical_explicit_pdsch_modulation_transform";
    codewords{cw} = info;
end
evidence = struct( ...
    "ContractVersion", "ExactPDSCHModulationEvidence/v1", ...
    "Codewords", {codewords}, ...
    "CodingPlanIDs", string(cellfun(@(plan) plan.PlanID, plans, ...
        "UniformOutput", false)), ...
    "Source", "canonical_tx_modulation_info");
end

function trace = localExactLayerMappingTrace(tx)
plans = localExactCodingPlans(tx);
if ~isfield(tx, "LayerMappingInfo") ...
        || ~isstruct(tx.LayerMappingInfo) ...
        || ~isfield(tx, "LayerSymbols")
    error("sixgr:pdsch:PDSCHWaveformBuilder:MissingLayerMappingEvidence", ...
        "Canonical PDSCH TX must expose LayerMappingInfo and materialized LayerSymbols.");
end
info = tx.LayerMappingInfo;
rankValue = double(sixgr.util.structGet(info, "Rank", NaN));
layerCounts = double(sixgr.util.structGet( ...
    info, "LayerCountPerCodeword", []));
codewordIndex = double(sixgr.util.structGet( ...
    info, "CodewordIndexPerLayer", []));
expectedLayerCounts = cellfun( ...
    @(plan) double(plan.NumLayers), plans);
if ~isequal(layerCounts(:).', expectedLayerCounts(:).') ...
        || rankValue ~= sum(expectedLayerCounts) ...
        || ~isequal(codewordIndex(:).', ...
            localCodewordIndexPerLayer(expectedLayerCounts))
    error("sixgr:pdsch:PDSCHWaveformBuilder:LayerMappingPlanMismatch", ...
        "Canonical layer-mapping evidence does not match exact per-codeword plan layers.");
end
if iscell(tx.LayerSymbols)
    materializedLayers = numel(tx.LayerSymbols);
else
    materializedLayers = size(tx.LayerSymbols, 2);
end
if materializedLayers ~= rankValue
    error("sixgr:pdsch:PDSCHWaveformBuilder:LayerMappingPlanMismatch", ...
        "Materialized canonical layer count %d does not match rank %d.", ...
        materializedLayers, rankValue);
end
layers = (0:(rankValue - 1)).';
codewordIndex = codewordIndex(:);
layerWithinCodeword = zeros(rankValue, 1);
layerCountForCodeword = zeros(rankValue, 1);
offset = 0;
for cw = 1:numel(layerCounts)
    count = layerCounts(cw);
    selected = offset + (1:count);
    layerWithinCodeword(selected) = (0:(count - 1)).';
    layerCountForCodeword(selected) = count;
    offset = offset + count;
end
if numel(layerCounts) == 1
    baselineMode = "nr_baseline_single_codeword";
else
    baselineMode = "nr_baseline_two_codeword";
end
trace = table(codewordIndex, layers, layerWithinCodeword, ...
    layerCountForCodeword, ...
    repmat("spatial_first_frequency_second_time_third", rankValue, 1), ...
    repmat(baselineMode, rankValue, 1), ...
    'VariableNames', {'CodewordIndex','LayerIndex', ...
    'LayerIndexWithinCodeword','LayerCountForCodeword', ...
    'MappingOrder','BaselineMode'});
end

function indices = localCodewordIndexPerLayer(layerCounts)
indices = zeros(1, sum(layerCounts));
offset = 0;
for cw = 1:numel(layerCounts)
    indices(offset + (1:layerCounts(cw))) = cw - 1;
    offset = offset + layerCounts(cw);
end
end

function plans = localExactCodingPlans(tx)
if ~isstruct(tx) || ~isfield(tx, "CodingPlans")
    error("sixgr:pdsch:PDSCHWaveformBuilder:MissingDLSCHCodingEvidence", ...
        "Canonical PDSCH TX must expose immutable CodingPlans.");
end
plans = tx.CodingPlans;
if isa(plans, "sixgr.pdsch.DLSCHCodingPlan")
    plans = {plans};
elseif iscell(plans)
    plans = reshape(plans, 1, []);
else
    plans = {};
end
if isempty(plans) || ~all(cellfun( ...
        @(plan) isa(plan, "sixgr.pdsch.DLSCHCodingPlan") ...
            && logical(plan.Immutable) ...
            && strlength(string(plan.PlanID)) > 0 ...
            && strlength(string(plan.CodingLayoutHash)) > 0, plans))
    error("sixgr:pdsch:PDSCHWaveformBuilder:MissingDLSCHCodingEvidence", ...
        "Canonical CodingPlans must contain immutable plans with IDs and layout hashes.");
end
end

