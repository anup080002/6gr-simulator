function localAssertPDSCHStudyMaterialization( ...
        pdsch, numLayers, rnti, cellId, fdraAlloc, tdraAlloc, ...
        symbolAllocation, amc, dmrsCfg, ptrsCfg)
requiredPDSCH = [ ...
    "Modulation","NumLayers","PRBSet","SymbolAllocation", ...
    "RNTI","NID","MappingType","DMRS","EnablePTRS"];
missing = requiredPDSCH(~arrayfun( ...
    @(name) isprop(pdsch, char(name)), requiredPDSCH));
if ~isempty(missing)
    error("sixgr:pdsch:PDSCHWaveformBuilder:UnsupportedToolboxPDSCHProperty", ...
        "Installed 5G Toolbox PDSCH configuration lacks required property/properties: %s.", ...
        strjoin(cellstr(missing), ", "));
end
expectedModulation = upper(string(localModulationForCodewords( ...
    amc.Modulation, numLayers)));
actualModulation = upper(string(pdsch.Modulation));
if ~isequal(actualModulation(:).', expectedModulation(:).') ...
        || double(pdsch.NumLayers) ~= double(numLayers) ...
        || ~isequal(double(pdsch.PRBSet(:).'), ...
            double(fdraAlloc.PRBSet(:).')) ...
        || ~isequal(double(pdsch.SymbolAllocation(:).'), ...
            double(symbolAllocation(:).')) ...
        || double(pdsch.RNTI) ~= double(rnti) ...
        || double(pdsch.NID) ~= double(cellId) ...
        || upper(string(pdsch.MappingType)) ~= ...
            upper(string(tdraAlloc.MappingType))
    error("sixgr:pdsch:PDSCHWaveformBuilder:PDSCHMaterializationMismatch", ...
        "Materialized PDSCH object does not exactly match scheduler modulation, rank, FDRA, TDRA, RNTI, NID, or MappingType.");
end

dmrs = pdsch.DMRS;
requiredDMRS = [ ...
    "DMRSConfigurationType","DMRSTypeAPosition", ...
    "DMRSAdditionalPosition","DMRSPortSet", ...
    "NumCDMGroupsWithoutData"];
missing = requiredDMRS(~arrayfun( ...
    @(name) isprop(dmrs, char(name)), requiredDMRS));
if ~isempty(missing)
    error("sixgr:pdsch:PDSCHWaveformBuilder:UnsupportedToolboxDMRSProperty", ...
        "Installed 5G Toolbox DM-RS configuration lacks required property/properties: %s.", ...
        strjoin(cellstr(missing), ", "));
end
expectedPorts = double(sixgr.util.structGet( ...
    dmrsCfg, "PortSet", 0:(numLayers - 1)));
if double(dmrs.DMRSConfigurationType) ~= double(sixgr.util.structGet( ...
        dmrsCfg, "ConfigType", 1)) ...
        || double(dmrs.DMRSTypeAPosition) ~= 2 ...
        || double(dmrs.DMRSAdditionalPosition) ~= double( ...
            sixgr.util.structGet(dmrsCfg, "AdditionalPosition", 1)) ...
        || ~isequal(double(dmrs.DMRSPortSet(:).'), ...
            double(expectedPorts(:).')) ...
        || double(dmrs.NumCDMGroupsWithoutData) ~= double( ...
            sixgr.util.structGet(dmrsCfg, "CDMGroupsWithoutData", 1))
    error("sixgr:pdsch:PDSCHWaveformBuilder:DMRSMaterializationMismatch", ...
        "Materialized DM-RS object does not exactly match the study configuration.");
end

expectedPTRSEnabled = logical(sixgr.util.structGet( ...
    ptrsCfg, "PTRSEnabled", false));
if logical(pdsch.EnablePTRS) ~= expectedPTRSEnabled
    error("sixgr:pdsch:PDSCHWaveformBuilder:PTRSMaterializationMismatch", ...
        "Materialized PT-RS enablement differs from the study configuration.");
end
if ~expectedPTRSEnabled
    return;
end
if ~isprop(pdsch, "PTRS")
    error("sixgr:pdsch:PDSCHWaveformBuilder:UnsupportedToolboxPTRSProperty", ...
        "Installed 5G Toolbox PDSCH configuration lacks required PTRS.");
end
ptrs = pdsch.PTRS;
requiredPTRS = ["TimeDensity","FrequencyDensity","REOffset","PTRSPortSet"];
missing = requiredPTRS(~arrayfun( ...
    @(name) isprop(ptrs, char(name)), requiredPTRS));
if ~isempty(missing)
    error("sixgr:pdsch:PDSCHWaveformBuilder:UnsupportedToolboxPTRSProperty", ...
        "Installed 5G Toolbox PT-RS configuration lacks required property/properties: %s.", ...
        strjoin(cellstr(missing), ", "));
end
expectedPTRSPort = expectedPorts(1);
if double(ptrs.TimeDensity) ~= double(sixgr.util.structGet( ...
        ptrsCfg, "TimeDensity", 2)) ...
        || double(ptrs.FrequencyDensity) ~= double(sixgr.util.structGet( ...
            ptrsCfg, "FrequencyDensity", 2)) ...
        || string(ptrs.REOffset) ~= string(sixgr.util.structGet( ...
            ptrsCfg, "REOffset", "00")) ...
        || ~isequal(double(ptrs.PTRSPortSet(:).'), ...
            double(expectedPTRSPort))
    error("sixgr:pdsch:PDSCHWaveformBuilder:PTRSMaterializationMismatch", ...
        "Materialized PT-RS object does not exactly match the study configuration.");
end
end

function [pdsch, amc, payloadBits, status, tbs] = localFitGrantToQueue(cfg, carrier, pdsch, amc, queueBits)
payloadBits = max(1, round(double(queueBits)));
status = "queue_fits_initial_grant";
tbs = NaN;
attempts = 0;
while attempts < 256
    tbs = sixgr.pdsch.TBSCalculator(carrier, pdsch, ...
        localStudyPerCodewordValue( ...
        amc.TargetCodeRate, pdsch.NumLayers, "TargetCodeRate"), 0);
    if localTotalBits(tbs) <= payloadBits
        return;
    end
    attempts = attempts + 1;
    if amc.MCSIndex > 0
        amc = localAMCFromIndex(cfg, amc.MCSIndex - 1);
        pdsch.Modulation = localModulationForCodewords(amc.Modulation, pdsch.NumLayers);
        status = "queue_limited_mcs_backoff_before_tx";
        continue;
    end
    if numel(pdsch.PRBSet) > 1
        pdsch.PRBSet = pdsch.PRBSet(1:end-1);
        status = "queue_limited_prb_backoff_before_tx";
        continue;
    end
    status = "queue_smaller_than_minimum_tbs_padding_applied_before_tx";
    return;
end
error("sixgr:pdsch:PDSCHWaveformBuilder:QueueFitFailed", ...
    "Unable to fit the scheduled PDSCH grant to the queue size.");
end

function amc = localAMCFromIndex(cfg, mcsIndex)
amc = sixgr.pdsch.AMCSelector(cfg, "EstimatedSNR_dB", cfg.SNRdB);
amc.MCSIndex = double(mcsIndex);
profile = sixgr.link.resolveMCSProfile(amc.MCSTable, amc.MCSIndex);
amc.Modulation = char(profile.Modulation);
amc.TargetCodeRate = double(profile.TargetCodeRate);
amc.SpectralEfficiency = double(profile.SpectralEfficiency);
end

function bits = localMakeTransportBlocks(tbsBits, payloadBits, seed)
rng(double(seed), "twister");
payloadBitCount = localPayloadBitCount(payloadBits);
tbsBits = double(tbsBits(:).');
if numel(tbsBits) > 1
    totalBits = sum(tbsBits);
    if payloadBitCount <= 0
        payloadVec = int8(randi([0 1], totalBits, 1));
    elseif isnumeric(payloadBits) && isscalar(payloadBits)
        payloadVec = int8(randi([0 1], payloadBitCount, 1));
    else
        payloadVec = int8(payloadBits(:) ~= 0);
    end
    bits = cell(1, numel(tbsBits));
    offset = 0;
    for c = 1:numel(tbsBits)
        n = round(tbsBits(c));
        bits{c} = int8(zeros(n, 1));
        take = min(n, max(0, numel(payloadVec) - offset));
        if take > 0
            bits{c}(1:take) = payloadVec(offset + (1:take));
        end
        if take < n
            bits{c}(take+1:end) = int8(randi([0 1], n - take, 1));
        end
        offset = offset + take;
    end
    return;
end
tbsBits = tbsBits(1);
if payloadBitCount <= 0
    payloadBits = int8(randi([0 1], tbsBits, 1));
elseif isnumeric(payloadBits) && isscalar(payloadBits)
    payloadBits = int8(randi([0 1], payloadBitCount, 1));
else
    payloadBits = int8(payloadBits(:) ~= 0);
end
bits = int8(zeros(tbsBits, 1));
L = min(tbsBits, numel(payloadBits));
if L > 0
    bits(1:L) = payloadBits(1:L);
end
if L < tbsBits
    bits(L+1:end) = int8(randi([0 1], tbsBits - L, 1));
end
end

function sizes = localTransportBlockSizes(bits)
if iscell(bits)
    sizes = double(cellfun(@numel, bits));
else
    sizes = double(numel(bits));
end
sizes = sizes(:).';
end

function total = localTotalBits(bits)
total = sum(double(bits(:)));
end

function n = localPDSCHCodewordCount(numLayers)
n = 1 + double(round(double(numLayers)) > 4);
end

function values = localStudyPerCodewordValue(raw, numLayers, name)
nCodewords = localPDSCHCodewordCount(numLayers);
values = double(raw(:).');
if numel(values) == 1
    values = repmat(values, 1, nCodewords);
end
if numel(values) ~= nCodewords || any(~isfinite(values))
    error("sixgr:pdsch:PDSCHWaveformBuilder:BadPerCodewordValue", ...
        "%s must resolve to exactly %d finite study-scheduler values.", ...
        char(string(name)), nCodewords);
end
end

function modulation = localModulationForCodewords(modulationIn, numLayers)
nCodewords = localPDSCHCodewordCount(numLayers);
tokens = string(modulationIn);
tokens = tokens(:).';
tokens = tokens(strlength(strtrim(tokens)) > 0);
if isempty(tokens)
    tokens = "QPSK";
end
if numel(tokens) == 1 && nCodewords > 1
    tokens = repmat(tokens, 1, nCodewords);
elseif numel(tokens) < nCodewords
    tokens(end+1:nCodewords) = tokens(end);
elseif numel(tokens) > nCodewords
    tokens = tokens(1:nCodewords);
end
if nCodewords == 1
    modulation = char(tokens(1));
else
    modulation = cellstr(tokens);
end
end

function tx = localApplyWidebandPhaseErrors(tx, cfg, copyIndex)
if ~logical(cfg.EnableWidebandUncalibratedPhaseErrors)
    return;
end
wave = sixgr.util.structGet(tx, "Waveform", []);
if isempty(wave) || size(wave, 2) <= 1
    return;
end
rng(double(cfg.Seed + 100 * copyIndex), "twister");
phaseOffsets = zeros(1, size(wave, 2));
phaseOffsets(2:end) = 2 * pi * rand(1, size(wave, 2) - 1);
tx.Waveform = wave .* exp(1j * phaseOffsets);
end

function count = localPayloadBitCount(payloadBits)
if isempty(payloadBits)
    count = 0;
elseif isnumeric(payloadBits) && isscalar(payloadBits)
    count = max(0, round(double(payloadBits)));
else
    count = numel(payloadBits);
end
end
