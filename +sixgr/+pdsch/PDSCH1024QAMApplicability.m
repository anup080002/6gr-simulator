classdef PDSCH1024QAMApplicability
    %PDSCH1024QAMAPPLICABILITY Release-18 guard plus pinned simulator policy.
    %
    % The UE capability remains a per-band, caller-supplied fact.  This
    % catalog independently proves that the named band belongs to the
    % declared frequency range, has a downlink, and matches the selected
    % deployment mode.  It therefore cannot be bypassed by setting the
    % caller eligibility booleans to true.

    methods (Static)
        function result = requireApplicable( ...
                frequencyRange, operatingBand, deploymentClass, ...
                dciFormat, rntiType, capabilityVariant, ...
                maxNumberMIMOLayersPDSCH, numLayers)
            frequencyRange = upper(strtrim(string(frequencyRange)));
            operatingBand = lower(strtrim(string(operatingBand)));
            deploymentClass = lower(strtrim(string(deploymentClass)));
            dciFormat = upper(strtrim(string(dciFormat)));
            rntiType = upper(strtrim(string(rntiType)));
            capabilityVariant = lower(strtrim(string(capabilityVariant)));
            if ~isscalar(frequencyRange) || ~isscalar(operatingBand) || ...
                    ~isscalar(deploymentClass) || ~isscalar(dciFormat) || ...
                    ~isscalar(rntiType) || ~isscalar(capabilityVariant)
                error("sixgr:pdsch:Invalid1024QAMApplicabilityContext", ...
                    char("FrequencyRange, OperatingBand, DeploymentClass, and " + ...
                    "DCIFormat/RNTIType/capability variant must be text scalars."));
            end
            if ~isnumeric(maxNumberMIMOLayersPDSCH)
                error("sixgr:pdsch:Invalid1024QAMMaxNumberMIMOLayersPDSCH", ...
                    char("MaxNumberMIMOLayersPDSCH must be an integer from " + ...
                    "1 through 8."));
            end
            if ~isnumeric(numLayers)
                error("sixgr:pdsch:Invalid1024QAMNumLayers", ...
                    "NumLayers must be an integer from 1 through 8.");
            end
            maxNumberMIMOLayersPDSCH = double(maxNumberMIMOLayersPDSCH);
            numLayers = double(numLayers);
            if ~(isscalar(maxNumberMIMOLayersPDSCH) && ...
                    isfinite(maxNumberMIMOLayersPDSCH) && ...
                    maxNumberMIMOLayersPDSCH == ...
                        fix(maxNumberMIMOLayersPDSCH) && ...
                    maxNumberMIMOLayersPDSCH >= 1 && ...
                    maxNumberMIMOLayersPDSCH <= 8)
                error("sixgr:pdsch:Invalid1024QAMMaxNumberMIMOLayersPDSCH", ...
                    char("MaxNumberMIMOLayersPDSCH must be an integer from " + ...
                    "1 through 8."));
            end
            if ~(isscalar(numLayers) && isfinite(numLayers) && ...
                    numLayers == fix(numLayers) && ...
                    numLayers >= 1 && numLayers <= 8)
                error("sixgr:pdsch:Invalid1024QAMNumLayers", ...
                    "NumLayers must be an integer from 1 through 8.");
            end

            capabilities = ...
                sixgr.pdsch.PDSCH1024QAMApplicability.capabilityCatalog();
            capabilityIndex = find( ...
                capabilities.CapabilityVariant == capabilityVariant, 1);
            if isempty(capabilityIndex)
                error("sixgr:pdsch:QAM1024CapabilityVariantNotInPinnedCatalog", ...
                    char("UECapability1024QAMVariant '%s' is not a pinned " + ...
                    "TS 38.306 per-band capability."), ...
                    char(capabilityVariant));
            end
            capability = capabilities(capabilityIndex, :);
            effectiveLayerLimit = min( ...
                maxNumberMIMOLayersPDSCH, capability.VariantLayerLimit);
            if numLayers > effectiveLayerLimit
                error("sixgr:pdsch:QAM1024LayerCapabilityExceeded", ...
                    char("PDSCH has %d layers, but capability %s with " + ...
                    "MaxNumberMIMOLayersPDSCH=%d permits at most %d " + ...
                    "1024QAM layers."), numLayers, char(capabilityVariant), ...
                    maxNumberMIMOLayersPDSCH, effectiveLayerLimit);
            end

            if frequencyRange ~= "FR1"
                error("sixgr:pdsch:QAM1024FrequencyRangeNotAllowed", ...
                    char("PDSCH 1024QAM is a per-band FR1 capability in the " + ...
                    "pinned Release-18 profile; '%s' is not applicable."), ...
                    char(frequencyRange));
            end

            bands = sixgr.pdsch.PDSCH1024QAMApplicability.bandCatalog();
            bandIndex = find(bands.OperatingBand == operatingBand, 1);
            if isempty(bandIndex)
                error("sixgr:pdsch:QAM1024BandNotInPinnedCatalog", ...
                    char("OperatingBand '%s' is absent from the pinned " + ...
                    "Release-18 NR operating-band catalog."), ...
                    char(operatingBand));
            end
            band = bands(bandIndex, :);
            if band.FrequencyRange ~= frequencyRange
                error("sixgr:pdsch:QAM1024BandRangeMismatch", ...
                    char("OperatingBand '%s' belongs to %s, not the declared " + ...
                    "frequency range %s."), char(operatingBand), ...
                    char(band.FrequencyRange), char(frequencyRange));
            end
            if ~band.DownlinkCapable
                error("sixgr:pdsch:QAM1024DownlinkBandRequired", ...
                    char("OperatingBand '%s' is %s-only and cannot carry " + ...
                    "PDSCH."), char(operatingBand), char(band.DuplexMode));
            end

            deployments = ...
                sixgr.pdsch.PDSCH1024QAMApplicability.deploymentCatalog();
            deploymentIndex = find( ...
                deployments.DeploymentClass == deploymentClass, 1);
            if isempty(deploymentIndex)
                error("sixgr:pdsch:QAM1024DeploymentClassNotInPinnedCatalog", ...
                    char("DeploymentClass '%s' is not a pinned PDSCH 1024QAM " + ...
                    "deployment binding."), char(deploymentClass));
            end
            deployment = deployments(deploymentIndex, :);
            if deployment.DuplexMode ~= band.DuplexMode
                error("sixgr:pdsch:QAM1024DeploymentBandMismatch", ...
                    char("DeploymentClass '%s' binds to %s, but OperatingBand " + ...
                    "'%s' requires %s."), char(deploymentClass), ...
                    char(deployment.DuplexMode), char(operatingBand), ...
                    char(band.DuplexMode));
            end

            formats = ...
                sixgr.pdsch.PDSCH1024QAMApplicability.dciFormatCatalog();
            formatIndex = find(formats.DCIFormat == dciFormat, 1);
            if isempty(formatIndex)
                error("sixgr:pdsch:QAM1024DCIFormatNotAllowed", ...
                    char("DCIFormat '%s' cannot select the Release-18 PDSCH " + ...
                    "1024QAM MCS table; expected DCI format 1_1, 1_2, " + ...
                    "or 1_3."), ...
                    char(dciFormat));
            end
            format = formats(formatIndex, :);
            if rntiType ~= format.AllowedRNTIType
                error("sixgr:pdsch:QAM1024RNTIProcedureNotAllowed", ...
                    char("DCIFormat %s can select the PDSCH 1024QAM table " + ...
                    "only when its CRC is scrambled by C-RNTI; got %s."), ...
                    char(dciFormat), char(rntiType));
            end

            result = struct( ...
                "Applicable", true, ...
                "CatalogVersion", ...
                    sixgr.pdsch.PDSCH1024QAMApplicability.catalogVersion(), ...
                "FrequencyRange", frequencyRange, ...
                "OperatingBand", operatingBand, ...
                "DuplexMode", band.DuplexMode, ...
                "DeploymentClass", deploymentClass, ...
                "DCIFormat", dciFormat, ...
                "RNTIType", rntiType, ...
                "CapabilityVariant", capabilityVariant, ...
                "MaxNumberMIMOLayersPDSCH", ...
                    maxNumberMIMOLayersPDSCH, ...
                "NumLayers", numLayers, ...
                "Effective1024QAMLayerLimit", effectiveLayerLimit, ...
                "CapabilitySource", capability.SourceField, ...
                "CapabilitySourceArchive", capability.SourceArchive, ...
                "CapabilitySourceArchiveSHA256", ...
                    capability.SourceArchiveSHA256, ...
                "BandSourceClause", band.SourceClause, ...
                "BandSourceArchive", band.SourceArchive, ...
                "BandSourceArchiveSHA256", band.SourceArchiveSHA256, ...
                "DeploymentBindingSource", deployment.BindingSource, ...
                "DCISelectionField", format.RRCSelectionField, ...
                "DCISourceClause", format.SourceClause, ...
                "DCISourceArchive", format.SourceArchive, ...
                "DCISourceArchiveSHA256", format.SourceArchiveSHA256);
        end

        function catalog = bandCatalog()
            % TS 38.101-1 V18.8.0, Table 5.2-1 (FR1), and
            % TS 38.101-2 V18.8.0, Table 5.2-1 (FR2).
            fdd = [ ...
                "n1","n2","n3","n5","n7","n8","n12","n13","n14", ...
                "n18","n20","n24","n25","n26","n28","n30","n31", ...
                "n65","n66","n70","n71","n72","n74","n85", ...
                "n91","n92","n93","n94","n100","n105","n106","n109"];
            tdd = [ ...
                "n34","n38","n39","n40","n41","n46","n47","n48", ...
                "n50","n51","n53","n54","n77","n78","n79","n90", ...
                "n96","n101","n102","n104"];
            sdl = ["n29","n67","n75","n76"];
            sul = [ ...
                "n80","n81","n82","n83","n84","n86","n89", ...
                "n95","n97","n98","n99"];
            fr21 = ["n257","n258","n259","n260","n261","n262"];
            fr22 = "n263";

            operatingBand = [fdd,tdd,sdl,sul,fr21,fr22].';
            frequencyRange = [ ...
                repmat("FR1", 1, numel(fdd) + numel(tdd) + ...
                    numel(sdl) + numel(sul)), ...
                repmat("FR2-1", 1, numel(fr21)), "FR2-2"].';
            duplexMode = [ ...
                repmat("FDD", 1, numel(fdd)), ...
                repmat("TDD", 1, numel(tdd)), ...
                repmat("SDL", 1, numel(sdl)), ...
                repmat("SUL", 1, numel(sul)), ...
                repmat("TDD", 1, numel(fr21) + numel(fr22))].';
            downlinkCapable = duplexMode ~= "SUL";
            sourceClause = repmat( ...
                "3GPP_TS_38_101_1_V18_8_0_TABLE_5_2_1", ...
                numel(operatingBand), 1);
            sourceClause(frequencyRange ~= "FR1") = ...
                "3GPP_TS_38_101_2_V18_8_0_TABLE_5_2_1";
            sourceArchive = repmat( ...
                "38101-1-i80.zip", numel(operatingBand), 1);
            sourceArchive(frequencyRange ~= "FR1") = ...
                "38101-2-i80.zip";
            sourceArchiveSHA256 = repmat( ...
                "d73d492aa8a87fad9cdd415e95fbaf7101852f077b78f4dbdda665084ec3ba0f", ...
                numel(operatingBand), 1);
            sourceArchiveSHA256(frequencyRange ~= "FR1") = ...
                "30117b861385c49d49c572ced81d6136e2349daea4da3a1142ab3362986337f2";
            bandNumber = str2double(extractAfter(operatingBand, 1));

            catalog = table( ...
                operatingBand, bandNumber, frequencyRange, duplexMode, ...
                downlinkCapable, sourceClause, sourceArchive, ...
                sourceArchiveSHA256, ...
                'VariableNames', { ...
                    'OperatingBand','BandNumber','FrequencyRange', ...
                    'DuplexMode','DownlinkCapable','SourceClause', ...
                    'SourceArchive','SourceArchiveSHA256'});
            catalog = sortrows(catalog, "BandNumber");
        end

        function catalog = deploymentCatalog()
            % fdd/tdd/sdl are direct bindings to Table 5.2-1 duplex modes.
            % The two controlled_* values are pinned simulator profiles,
            % both explicitly bound to TDD; arbitrary labels are rejected.
            deploymentClass = [ ...
                "fdd";"tdd";"sdl"; ...
                "controlled_test";"controlled_coverage"];
            duplexMode = ["FDD";"TDD";"SDL";"TDD";"TDD"];
            bindingSource = [ ...
                "3GPP_TS_38_101_1_V18_8_0_TABLE_5_2_1"; ...
                "3GPP_TS_38_101_1_V18_8_0_TABLE_5_2_1"; ...
                "3GPP_TS_38_101_1_V18_8_0_TABLE_5_2_1"; ...
                "PROMPT02_PINNED_TDD_TEST_PROFILE"; ...
                "PROMPT02_PINNED_TDD_COVERAGE_PROFILE"];
            catalog = table( ...
                deploymentClass, duplexMode, bindingSource, ...
                'VariableNames', { ...
                    'DeploymentClass','DuplexMode','BindingSource'});
        end

        function catalog = capabilityCatalog()
            capabilityVariant = [ ...
                "pdsch-1024qam-fr1-r17"; ...
                "pdsch-1024qam-2mimo-fr1-r17"];
            variantLayerLimit = [8;2];
            mutualExclusionGroup = repmat( ...
                "pdsch_1024qam_fr1_r17_per_band", 2, 1);
            sourceField = [ ...
                "TS_38_306_V18_8_0_pdsch-1024QAM-FR1-r17"; ...
                "TS_38_306_V18_8_0_pdsch-1024QAM-2MIMO-FR1-r17"];
            sourceArchive = repmat("38306-i80.zip", 2, 1);
            sourceArchiveSHA256 = repmat( ...
                "5d237e4832df12cbd0ed1c736a19d92ea054bf325553704f85b566fbfb18ef0e", ...
                2, 1);
            catalog = table( ...
                capabilityVariant, variantLayerLimit, ...
                mutualExclusionGroup, sourceField, sourceArchive, ...
                sourceArchiveSHA256, ...
                'VariableNames', { ...
                    'CapabilityVariant','VariantLayerLimit', ...
                    'MutualExclusionGroup','SourceField', ...
                    'SourceArchive','SourceArchiveSHA256'});
        end

        function catalog = dciFormatCatalog()
            dciFormat = ["1_1";"1_2";"1_3"];
            rrcSelectionField = [ ...
                "mcs-Table-r17"; ...
                "mcs-TableDCI-1-2-r17"; ...
                "mcs-Table-r17"];
            allowedRNTIType = repmat("C-RNTI", 3, 1);
            sourceClause = repmat( ...
                "3GPP_TS_38_214_V18_8_0_CLAUSE_5_1_3_1", 3, 1);
            sourceArchive = repmat("38214-i80.zip", 3, 1);
            sourceArchiveSHA256 = repmat( ...
                "46b5d9be58e0fc1dcab368a27f5ffdee8c94c48327bd65d3abbfc00f602136fa", ...
                3, 1);
            catalog = table( ...
                dciFormat, rrcSelectionField, allowedRNTIType, ...
                sourceClause, sourceArchive, sourceArchiveSHA256, ...
                'VariableNames', { ...
                    'DCIFormat','RRCSelectionField','AllowedRNTIType', ...
                    'SourceClause','SourceArchive', ...
                    'SourceArchiveSHA256'});
        end

        function value = catalogVersion()
            value = "PDSCH_1024QAM_REL18_V2";
        end
    end
end
