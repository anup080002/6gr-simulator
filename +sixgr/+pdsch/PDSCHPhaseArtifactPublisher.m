classdef PDSCHPhaseArtifactPublisher
    %PDSCHPHASEARTIFACTPUBLISHER Assemble observed PDSCH phase artifacts.
    %
    % This class owns the non-test-specific part of phase publication.  It
    % writes production-derived tables and figures into a fresh staging
    % directory, records measured execution evidence, and exposes the same
    % artifact-only path to the standalone artifact test.  It does not
    % synthesize a testPDSCHArtifactGeneration result; that row is added only
    % by recordValidation after the real validator has inspected the stage.

    methods (Static)
        function names = promptMandatoryTestSuiteNames()
            %PROMPTMANDATORYTESTSUITENAMES Exact Prompt-02 acceptance set.
            %
            % Repository-only regressions remain in the focused executor
            % catalog but are not relabeled as prompt-mandatory tests.
            names = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                mandatoryTestSuiteNames();
        end

        function assembly = prepare(builder, coverage, testSummary, ...
                preExecution, stageDir, vectorRoot)
            stageDir = char(string(stageDir));
            vectorRoot = char(string(vectorRoot));
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                requireFreshDirectory(stageDir);
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateBuilder(builder);
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateCoverage(coverage);
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateExecutionTable(preExecution, "preExecution");

            testSummary = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateTestSummary(testSummary, false);
            tables = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                mergePrimaryTables(builder, coverage, vectorRoot);
            tables.pdsch_test_summary = testSummary;
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validatePrimaryRows(tables);
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateNegativeEvidence(tables.pdsch_negative_tests);
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateBLEREvidence(tables.pdsch_bler_curve);
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateDigestEvidence(tables);

            exportStarted = tic;
            exportSummary = sixgr.pdsch.PDSCHArtifactExporter.export( ...
                tables, stageDir, vectorRoot);
            exportDuration = toc(exportStarted);
            if ~isstruct(exportSummary) || ~isscalar(exportSummary) ...
                    || ~isfield(exportSummary, "Passed")
                error("sixgr:pdsch:PDSCHPhasePublisher:BadExporterResult", ...
                    "PDSCHArtifactExporter returned an invalid result.");
            end
            exportedNames = [ ...
                string(exportSummary.CSVFiles(:)); ...
                string(exportSummary.ContractedPNGFiles(:)); ...
                string(exportSummary.AdditionalPNGFiles(:))];
            exportStatuses = repmat( ...
                string(sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                ternary(logical(exportSummary.Passed), "PASS", "FAIL")), ...
                numel(exportedNames), 1);
            exportRow = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                executionRow( ...
                "artifact_export", ...
                "sixgr.pdsch.PDSCHArtifactExporter.export", ...
                "transactional_matlab_export", ...
                exportStatuses, exportDuration, ...
                "csv=" + string(numel(exportSummary.CSVFiles)) ...
                + " png=" + string( ...
                numel(exportSummary.ContractedPNGFiles) ...
                + numel(exportSummary.AdditionalPNGFiles)));
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                requirePassingExecution(exportRow, "artifact export");

            extraFiles = [ ...
                "pdsch_declared_coverage_results.csv"; ...
                "pdsch_pairwise_cases.csv"; ...
                "pdsch_no_noise_roundtrip.csv"; ...
                "pdsch_phase_execution_summary.csv"];
            writetable(coverage.DeclaredCoverageResults, ...
                fullfile(stageDir, extraFiles(1)), "Encoding", "UTF-8");
            writetable(coverage.PairwiseCases, ...
                fullfile(stageDir, extraFiles(2)), "Encoding", "UTF-8");
            writetable(coverage.NoNoiseRoundTrip, ...
                fullfile(stageDir, extraFiles(3)), "Encoding", "UTF-8");

            phaseExecution = [preExecution; exportRow];
            writetable(phaseExecution, fullfile(stageDir, extraFiles(4)), ...
                "Encoding", "UTF-8");

            contractStarted = tic;
            inventory = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                inventory(stageDir);
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateInventory(inventory, 19, 11, ...
                "MATLAB pre-verifier artifact contract");
            contractDuration = toc(contractStarted);
            contractRow = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                executionRow( ...
                "matlab_output_contract", ...
                "sixgr.pdsch.PDSCHPhaseArtifactPublisher.inventory", ...
                "filesystem_inventory", inventory.Status, ...
                contractDuration, ...
                "csv=" + string(nnz(inventory.Kind == "CSV")) ...
                + " png=" + string(nnz(inventory.Kind == "PNG")));
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                requirePassingExecution(contractRow, ...
                "MATLAB output contract");
            phaseExecution = [phaseExecution; contractRow];
            writetable(phaseExecution, fullfile(stageDir, extraFiles(4)), ...
                "Encoding", "UTF-8");
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateNoCopiedExpectedCSVs(stageDir, vectorRoot);

            inventory = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                inventory(stageDir);
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateInventory(inventory, 19, 11, ...
                "MATLAB pre-verifier artifact contract");

            assembly = struct( ...
                "Passed", all(phaseExecution.Status == "PASS") ...
                    && all(inventory.Status == "PASS"), ...
                "StageDir", string(stageDir), ...
                "VectorRoot", string(vectorRoot), ...
                "Tables", tables, ...
                "TestSummary", testSummary, ...
                "PhaseExecutionSummary", phaseExecution, ...
                "ArtifactInventory", inventory, ...
                "ExporterSummary", exportSummary, ...
                "AdditionalCSVFiles", extraFiles);
            if ~logical(assembly.Passed)
                error("sixgr:pdsch:PDSCHPhasePublisher:PreparationFailed", ...
                    "Observed phase preparation evidence did not pass.");
            end
        end

        function finalized = recordValidation(assembly, validation)
            requiredAssembly = [ ...
                "StageDir","VectorRoot","Tables","TestSummary", ...
                "PhaseExecutionSummary","ArtifactInventory", ...
                "ExporterSummary","AdditionalCSVFiles"];
            if ~isstruct(assembly) || ~isscalar(assembly) ...
                    || any(~isfield(assembly, requiredAssembly))
                error("sixgr:pdsch:PDSCHPhasePublisher:BadAssembly", ...
                    "Artifact assembly is incomplete.");
            end
            stageDir = char(string(assembly.StageDir));
            if ~isfolder(stageDir)
                error("sixgr:pdsch:PDSCHPhasePublisher:StageMissing", ...
                    "Artifact stage no longer exists: %s", stageDir);
            end
            validation = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateArtifactResult(validation);
            if ~logical(validation.Passed)
                error("sixgr:pdsch:PDSCHPhasePublisher:ValidationFailed", ...
                    "Artifact validation cannot be recorded as passing.");
            end

            testSummary = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateTestSummary(assembly.TestSummary, false);
            suiteName = "testPDSCHArtifactGeneration";
            if any(string(testSummary.TestSuite) == suiteName)
                error("sixgr:pdsch:PDSCHPhasePublisher:DuplicateArtifactTest", ...
                    "Artifact-generation validation has already been recorded.");
            end
            statuses = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                normalizeStatuses(validation.CheckStatuses);
            passedCount = nnz(statuses == "PASS");
            failedCount = nnz(statuses == "FAIL");
            suiteStatus = string( ...
                sixgr.pdsch.PDSCHPhaseArtifactPublisher.ternary( ...
                ~isempty(statuses) && failedCount == 0, "PASS", "FAIL"));
            artifactSummaryRow = struct2table(struct( ...
                "TestSuite", suiteName, ...
                "Total", double(numel(statuses)), ...
                "Passed", double(passedCount), ...
                "Failed", double(failedCount), ...
                "Skipped", 0, ...
                "Blocked", 0, ...
                "Status", suiteStatus));
            testSummary = [testSummary; artifactSummaryRow];
            testSummary = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateTestSummary(testSummary, true);
            writetable(testSummary, ...
                fullfile(stageDir, "pdsch_test_summary.csv"), ...
                "Encoding", "UTF-8");

            detail = "verifier_exit=" + string(validation.VerifierExitCode) ...
                + " csv=" + string(validation.CSVCount) ...
                + " png=" + string(validation.PNGCount);
            artifactExecution = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                executionRow( ...
                "focused_test_function", suiteName, ...
                "real_stage_export_and_python_verification", ...
                statuses, double(validation.DurationSeconds), detail, ...
                string(validation.ErrorIdentifier), ...
                string(validation.ErrorMessage));
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                requirePassingExecution(artifactExecution, ...
                "artifact-generation test");

            phaseExecution = assembly.PhaseExecutionSummary;
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateExecutionTable(phaseExecution, ...
                "assembly.PhaseExecutionSummary");
            phaseExecution = [phaseExecution; artifactExecution];
            writetable(phaseExecution, fullfile(stageDir, ...
                "pdsch_phase_execution_summary.csv"), ...
                "Encoding", "UTF-8");
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateNoCopiedExpectedCSVs( ...
                stageDir, char(string(assembly.VectorRoot)));

            inventory = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                inventory(stageDir);
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateInventory(inventory, 20, 11, ...
                "post-verifier artifact contract");

            exportSummary = assembly.ExporterSummary;
            summaryMask = string(exportSummary.CSVFiles) ...
                == "pdsch_test_summary.csv";
            if nnz(summaryMask) ~= 1
                error("sixgr:pdsch:PDSCHPhasePublisher:ExporterSummaryMismatch", ...
                    "Exporter result does not identify pdsch_test_summary.csv.");
            end
            exportSummary.CSVRowCounts(summaryMask) = height(testSummary);
            tables = assembly.Tables;
            tables.pdsch_test_summary = testSummary;
            finalized = assembly;
            finalized.Passed = all(phaseExecution.Status == "PASS") ...
                && all(inventory.Status == "PASS") ...
                && logical(validation.Passed);
            finalized.Tables = tables;
            finalized.TestSummary = testSummary;
            finalized.PhaseExecutionSummary = phaseExecution;
            finalized.ArtifactInventory = inventory;
            finalized.ExporterSummary = exportSummary;
            finalized.ArtifactValidation = validation;
            if ~logical(finalized.Passed)
                error("sixgr:pdsch:PDSCHPhasePublisher:FinalizationFailed", ...
                    "Recorded artifact validation is not fully passing.");
            end
        end

        function row = executionRow(stage, source, executionMode, ...
                recordStatuses, durationSeconds, detail, ...
                errorIdentifier, errorMessage)
            if nargin < 6
                detail = "";
            end
            if nargin < 7
                errorIdentifier = "";
            end
            if nargin < 8
                errorMessage = "";
            end
            statuses = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                normalizeStatuses(recordStatuses);
            durationSeconds = double(durationSeconds);
            if ~(isscalar(durationSeconds) && isfinite(durationSeconds) ...
                    && durationSeconds >= 0)
                error("sixgr:pdsch:PDSCHPhasePublisher:BadDuration", ...
                    "Stage duration must be a finite nonnegative scalar.");
            end
            recordCount = numel(statuses);
            passedCount = nnz(statuses == "PASS");
            failedCount = nnz(statuses == "FAIL");
            status = string( ...
                sixgr.pdsch.PDSCHPhaseArtifactPublisher.ternary( ...
                recordCount > 0 && failedCount == 0, "PASS", "FAIL"));
            row = struct2table(struct( ...
                "Stage", string(stage), ...
                "Source", string(source), ...
                "ExecutionMode", string(executionMode), ...
                "RecordCount", double(recordCount), ...
                "PassedCount", double(passedCount), ...
                "FailedCount", double(failedCount), ...
                "DurationSeconds", durationSeconds, ...
                "ErrorIdentifier", string(errorIdentifier), ...
                "ErrorMessage", string(errorMessage), ...
                "Detail", string(detail), ...
                "Status", status));
        end

        function value = inventory(outputDir)
            outputDir = char(string(outputDir));
            files = [dir(fullfile(outputDir, "*.csv")); ...
                dir(fullfile(outputDir, "*.png"))];
            if isempty(files)
                error("sixgr:pdsch:PDSCHPhasePublisher:NoArtifacts", ...
                    "No PDSCH phase artifacts were generated.");
            end
            [~, order] = sort(string({files.name}));
            files = files(order);
            FileName = strings(numel(files), 1);
            Kind = strings(numel(files), 1);
            Bytes = zeros(numel(files), 1);
            Width = zeros(numel(files), 1);
            Height = zeros(numel(files), 1);
            SHA256 = strings(numel(files), 1);
            Status = strings(numel(files), 1);
            for i = 1:numel(files)
                FileName(i) = string(files(i).name);
                path = fullfile(outputDir, files(i).name);
                Bytes(i) = double(files(i).bytes);
                [~, ~, extension] = fileparts(files(i).name);
                if strcmpi(extension, ".png")
                    Kind(i) = "PNG";
                    info = imfinfo(path);
                    Width(i) = double(info.Width);
                    Height(i) = double(info.Height);
                else
                    Kind(i) = "CSV";
                end
                SHA256(i) = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                    fileSHA256(path);
                valid = Bytes(i) > 0 && strlength(SHA256(i)) == 64;
                if Kind(i) == "PNG"
                    valid = valid && Width(i) >= 900 && Height(i) >= 600;
                end
                Status(i) = string( ...
                    sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                    ternary(valid, "PASS", "FAIL"));
            end
            value = table( ...
                FileName, Kind, Bytes, Width, Height, SHA256, Status);
        end

        function validateInventory(value, expectedCSV, expectedPNG, label)
            if ~istable(value) || isempty(value)
                error("sixgr:pdsch:PDSCHPhasePublisher:EmptyInventory", ...
                    "%s is empty.", label);
            end
            required = [ ...
                "FileName","Kind","Bytes","Width","Height","SHA256","Status"];
            if any(~ismember(required, ...
                    string(value.Properties.VariableNames)))
                error("sixgr:pdsch:PDSCHPhasePublisher:BadInventorySchema", ...
                    "%s has an invalid schema.", label);
            end
            if any(upper(string(value.Status)) ~= "PASS")
                error("sixgr:pdsch:PDSCHPhasePublisher:ArtifactIntegrityFailed", ...
                    "%s contains a non-passing file.", label);
            end
            csvCount = nnz(string(value.Kind) == "CSV");
            pngCount = nnz(string(value.Kind) == "PNG");
            if csvCount ~= expectedCSV || pngCount ~= expectedPNG
                error("sixgr:pdsch:PDSCHPhasePublisher:ArtifactCountMismatch", ...
                    "%s expected %d CSVs and %d PNGs; observed %d and %d.", ...
                    label, expectedCSV, expectedPNG, csvCount, pngCount);
            end
            if any(startsWith(string(value.FileName), "expected_"))
                error("sixgr:pdsch:PDSCHPhasePublisher:ExpectedArtifactCopied", ...
                    "Expected-vector CSV files must not be published.");
            end
        end
    end

    methods (Static, Access = private)
        function requireFreshDirectory(path)
            if strlength(strtrim(string(path))) == 0
                error("sixgr:pdsch:PDSCHPhasePublisher:MissingStage", ...
                    "Artifact stage path must be nonempty.");
            end
            if isfile(path)
                error("sixgr:pdsch:PDSCHPhasePublisher:StageIsFile", ...
                    "Artifact stage resolves to a file: %s", path);
            end
            if isfolder(path)
                entries = dir(path);
                names = string({entries.name});
                entries = entries(~ismember(names, [".",".."]));
                if ~isempty(entries)
                    error("sixgr:pdsch:PDSCHPhasePublisher:StageNotEmpty", ...
                        "Artifact stage must be empty: %s", path);
                end
                return;
            end
            parent = fileparts(path);
            if ~isempty(parent) && ~isfolder(parent)
                [created, message] = mkdir(parent);
                if ~created
                    error("sixgr:pdsch:PDSCHPhasePublisher:ParentCreateFailed", ...
                        "Unable to create artifact parent: %s", message);
                end
            end
            [created, message] = mkdir(path);
            if ~created
                error("sixgr:pdsch:PDSCHPhasePublisher:StageCreateFailed", ...
                    "Unable to create artifact stage: %s", message);
            end
        end

        function validateBuilder(builder)
            expected = [ ...
                "pdsch_assignment_resolution"; ...
                "pdsch_resource_ownership"; ...
                "pdsch_re_mapping"; ...
                "pdsch_dmrs_matrix"; ...
                "pdsch_ptrs_matrix"; ...
                "pdsch_coding_chain"; ...
                "pdsch_independent_vector_results"; ...
                "pdsch_layer_codeword_map"; ...
                "pdsch_precoding_application"; ...
                "pdsch_harq_trials"; ...
                "pdsch_negative_tests"];
            if ~isstruct(builder) || ~isscalar(builder) ...
                    || ~isequal(sort(string(fieldnames(builder))), ...
                    sort(expected))
                error("sixgr:pdsch:PDSCHPhasePublisher:BuilderMismatch", ...
                    "Evidence builder returned an unexpected contract.");
            end
            for name = expected.'
                sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                    requirePassingTable(builder.(name), "builder." + name);
            end
        end

        function validateCoverage(coverage)
            required = [ ...
                "Passed","DeclaredCoverageResults","PairwiseCases", ...
                "NoNoiseRoundTrip","ReceiverMetrics","BLERCurve", ...
                "NegativeTests","TestSummary","FadingTruthAnchors"];
            if ~isstruct(coverage) || ~isscalar(coverage) ...
                    || any(~isfield(coverage, required))
                error("sixgr:pdsch:PDSCHPhasePublisher:CoverageMismatch", ...
                    "Coverage executor returned an incomplete contract.");
            end
            if ~logical(coverage.Passed)
                error("sixgr:pdsch:PDSCHPhasePublisher:CoverageFailed", ...
                    "Coverage executor returned Passed=false.");
            end
            for name = required(2:end)
                sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                    requirePassingTable(coverage.(name), ...
                    "coverage." + name);
            end
        end

        function tables = mergePrimaryTables(builder, coverage, vectorRoot)
            tables = builder;
            tables.pdsch_receiver_metrics = coverage.ReceiverMetrics;
            tables.pdsch_bler_curve = coverage.BLERCurve;
            builderNegatives = sixgr.pdsch. ...
                PDSCHPhaseArtifactPublisher.contractTextTable( ...
                builder.pdsch_negative_tests, vectorRoot, ...
                "pdsch_negative_tests.csv");
            coverageNegatives = sixgr.pdsch. ...
                PDSCHPhaseArtifactPublisher.contractTextTable( ...
                coverage.NegativeTests, vectorRoot, ...
                "pdsch_negative_tests.csv");
            % One primary table carries every observed pre-waveform reject:
            % frozen vector negatives, declared receiver/preflight negatives,
            % and the mandatory cross-component integration negatives.
            tables.pdsch_negative_tests = [ ...
                builderNegatives; coverageNegatives];
        end

        function output = contractTextTable(input, vectorRoot, fileName)
            contract = readtable(fullfile(vectorRoot, ...
                "desired_pdsch_csv_contract.csv"), ...
                "TextType", "string", ...
                "VariableNamingRule", "preserve");
            match = contract.FileName == string(fileName);
            if nnz(match) ~= 1
                error("sixgr:pdsch:PDSCHPhasePublisher:ContractRowMissing", ...
                    "Missing unique CSV contract row for %s.", fileName);
            end
            expected = split(contract.RequiredColumns(match), "|").';
            actual = string(input.Properties.VariableNames);
            if ~isequal(actual, expected)
                error("sixgr:pdsch:PDSCHPhasePublisher:CoverageSchemaMismatch", ...
                    "%s schema differs from the artifact contract.", ...
                    fileName);
            end
            output = table();
            for name = expected
                column = input.(name);
                if islogical(column) || isnumeric(column)
                    output.(name) = string(column);
                else
                    output.(name) = string(column);
                end
                output.(name)(ismissing(output.(name))) = "";
            end
        end

        function validatePrimaryRows(tables)
            names = string(fieldnames(tables));
            for name = names.'
                sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                    requirePassingTable(tables.(name), ...
                    "primary." + name);
            end
        end

        function validateNegativeEvidence(value)
            vectorFamily = [ ...
                "assignment_resolution"; ...
                "dmrs_symbol_configuration"; ...
                "dmrs_port_table"; ...
                "ptrs_presence"; ...
                "reserved_re_union"; ...
                "tbs_independent_scalar_input_contract"; ...
                "qam_modulation"; ...
                "codeword_layer_mapping"; ...
                "precoder_bundle"; ...
                "harq_transition"];
            vectorFloor = [16;42;18;3;3;5;4;4;6;5];
            families = lower(strtrim(string(value.TestKind)));
            for i = 1:numel(vectorFamily)
                observed = nnz(families == vectorFamily(i));
                if observed < vectorFloor(i)
                    error( ...
                        "sixgr:pdsch:PDSCHPhasePublisher:NegativeFamilyFloorMismatch", ...
                        "Negative family %s requires at least %d rows; observed %d.", ...
                        vectorFamily(i), vectorFloor(i), observed);
                end
            end
            declaredFamily = [ ...
                "no_signal";"wrong_rnti";"wrong_dmrs";"wrong_rv"];
            for family = declaredFamily.'
                observed = nnz(families == family);
                if observed < 16
                    error( ...
                        "sixgr:pdsch:PDSCHPhasePublisher:DeclaredNegativeMissing", ...
                        "Declared negative family %s requires 16 observed rows.", ...
                        family);
                end
            end
            integration = sixgr.pdsch.PDSCHCoverageExecutor. ...
                integrationNegativeContract();
            for i = 1:height(integration)
                hit = families == integration.TestKind(i);
                if nnz(hit) ~= 1
                    error( ...
                        "sixgr:pdsch:PDSCHPhasePublisher:IntegrationNegativeMissing", ...
                        "Expected exactly one observed integration row for %s.", ...
                        integration.TestKind(i));
                end
                if string(value.ExpectedErrorIdentifier(hit)) ~= ...
                        integration.ExpectedErrorIdentifier(i)
                    error( ...
                        "sixgr:pdsch:PDSCHPhasePublisher:IntegrationNegativeIDMismatch", ...
                        "Integration negative %s has the wrong expected identifier.", ...
                        integration.TestKind(i));
                end
            end
            expected = strtrim(string(value.ExpectedErrorIdentifier));
            actual = strtrim(string(value.ActualErrorIdentifier));
            if any(strlength(expected) == 0 | expected ~= actual)
                error("sixgr:pdsch:PDSCHPhasePublisher:NegativeTypedIDMismatch", ...
                    "Every negative row must contain the exact nonblank " + ...
                    "expected and observed typed MATLAB identifier.");
            end
            generated = upper(strtrim(string(value.WaveformGenerated)));
            if any(~ismember(generated, ["0","FALSE","NO","N","FAIL"]))
                error("sixgr:pdsch:PDSCHPhasePublisher:NegativeWaveformGenerated", ...
                    "No negative case may generate a waveform.");
            end
            caseID = strtrim(string(value.CaseID));
            if any(strlength(caseID) == 0) ...
                    || numel(unique(caseID)) ~= numel(caseID)
                error("sixgr:pdsch:PDSCHPhasePublisher:NegativeCaseIDInvalid", ...
                    "Negative evidence requires nonblank unique CaseID values.");
            end
            requiredIdentifiers = sixgr.pdsch. ...
                PDSCHPhaseArtifactPublisher. ...
                mandatoryNegativeIdentifiers();
            missing = setdiff(requiredIdentifiers,unique(expected),"stable");
            if ~isempty(missing)
                error( ...
                    "sixgr:pdsch:PDSCHPhasePublisher:MandatoryNegativeIdentifierMissing", ...
                    "Mandatory negative identifiers are missing: %s.", ...
                    strjoin(cellstr(missing),", "));
            end
        end

