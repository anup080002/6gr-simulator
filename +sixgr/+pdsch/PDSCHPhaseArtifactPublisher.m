        function validateNoCopiedExpectedCSVs(stageDir, vectorRoot)
            if ~isfolder(vectorRoot)
                error("sixgr:pdsch:PDSCHPhasePublisher:VectorRootMissing", ...
                    "Vector root does not exist: %s", vectorRoot);
            end
            expectedFiles = dir(fullfile(vectorRoot, "**", ...
                "expected_*.csv"));
            expectedFiles = expectedFiles(~[expectedFiles.isdir]);
            if isempty(expectedFiles)
                error("sixgr:pdsch:PDSCHPhasePublisher:ExpectedVectorsMissing", ...
                    "No frozen expected CSVs were found under VectorRoot.");
            end
            outputFiles = dir(fullfile(stageDir, "*.csv"));
            for i = 1:numel(outputFiles)
                outputPath = fullfile(outputFiles(i).folder, ...
                    outputFiles(i).name);
                outputHash = sixgr.pdsch. ...
                    PDSCHPhaseArtifactPublisher.fileSHA256(outputPath);
                for j = 1:numel(expectedFiles)
                    expectedPath = fullfile(expectedFiles(j).folder, ...
                        expectedFiles(j).name);
                    expectedHash = sixgr.pdsch. ...
                        PDSCHPhaseArtifactPublisher.fileSHA256(expectedPath);
                    if outputHash == expectedHash
                        error( ...
                            "sixgr:pdsch:PDSCHPhasePublisher:ExpectedArtifactCopied", ...
                            "Published CSV %s is byte-identical to frozen " + ...
                            "expected vector %s.", ...
                            outputFiles(i).name, expectedPath);
                    end
                end
            end
        end

        function requireHex64(value, fields, label)
            fields = string(fields(:));
            for field = fields.'
                raw = string(value.(field));
                valid = ~cellfun("isempty", regexp(cellstr(raw), ...
                    "^[0-9A-Fa-f]{64}$", "once"));
                if any(~valid)
                    error("sixgr:pdsch:PDSCHPhasePublisher:DigestInvalid", ...
                        "%s has a non-64-hex value in %s.", ...
                        label, field);
                end
            end
        end

