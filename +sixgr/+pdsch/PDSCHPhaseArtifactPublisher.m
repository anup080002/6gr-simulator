        function validateBLEREvidence(value)
            campaignIDs = [ ...
                "BLER-AWGN-QPSK"; ...
                "BLER-AWGN-64QAM"; ...
                "BLER-TDL-R2-16QAM"; ...
                "BLER-CDL-R4-64QAM"; ...
                "BLER-AWGN-1024QAM"; ...
                "BLER-AWGN-HARQ-0231"; ...
                "BLER-AWGN-PTRS-PN"];
            channels = [ ...
                "AWGN";"AWGN";"TDL-A";"CDL-C"; ...
                "AWGN";"AWGN";"AWGN"];
            ranks = [1;1;2;4;1;1;1];
            modulations = [ ...
                "QPSK";"64QAM";"16QAM";"64QAM"; ...
                "1024QAM";"QPSK";"256QAM"];
            % R2026a's Release-18 qam1024 table exposes index 23 as the
            % enabled 1024QAM campaign entry; index 27 is reserved.  The
            % artifact contract must name the entry actually resolved and
            % executed by PDSCHMCSResolver.
            mcsIndices = [4;18;10;18;23;4;25];
            observedIDs = string(value.CampaignID);
            if height(value) ~= 28 ...
                    || ~isempty(setxor(unique(observedIDs), campaignIDs))
                error("sixgr:pdsch:PDSCHPhasePublisher:BLERCampaignMismatch", ...
                    "BLER evidence must contain exactly seven mandatory " + ...
                    "campaigns with four operating points each.");
            end
            for i = 1:numel(campaignIDs)
                mask = observedIDs == campaignIDs(i);
                if nnz(mask) ~= 4 ...
                        || numel(unique(string( ...
                        value.OperatingPointID(mask)))) ~= 4 ...
                        || any(upper(string( ...
                        value.ChannelModel(mask))) ~= channels(i)) ...
                        || any(sixgr.pdsch. ...
                        PDSCHPhaseArtifactPublisher.numericColumn( ...
                        value.Rank(mask)) ~= ranks(i)) ...
                        || any(upper(string( ...
                        value.Modulation(mask))) ~= modulations(i)) ...
                        || any(sixgr.pdsch. ...
                        PDSCHPhaseArtifactPublisher.numericColumn( ...
                        value.MCSIndex(mask)) ~= mcsIndices(i))
                    error( ...
                        "sixgr:pdsch:PDSCHPhasePublisher:BLERCampaignMetadataMismatch", ...
                        "BLER campaign %s differs from its fixed contract.", ...
                        campaignIDs(i));
                end
            end
            trials = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                numericColumn(value.Trials);
            errors = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                numericColumn(value.TBErrors);
            bler = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                numericColumn(value.BLER);
            confidence = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                numericColumn(value.ConfidenceLevel);
            lowerBound = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                numericColumn(value.CILower);
            upperBound = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                numericColumn(value.CIUpper);
            halfWidth = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                numericColumn(value.CIHalfWidth);
            minimumErrors = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                numericColumn(value.MinErrorsRequired);
            validCounts = isfinite(trials) & trials >= 4 ...
                & trials == fix(trials) & isfinite(errors) ...
                & errors >= 0 & errors == fix(errors) & errors <= trials;
            validBounds = isfinite(bler) & bler >= 0 & bler <= 1 ...
                & isfinite(confidence) & confidence > 0 & confidence < 1 ...
                & isfinite(lowerBound) & lowerBound >= 0 ...
                & isfinite(upperBound) & upperBound <= 1 ...
                & lowerBound <= bler & bler <= upperBound ...
                & isfinite(halfWidth) & halfWidth >= 0 ...
                & abs(halfWidth - (upperBound-lowerBound)/2) <= 1e-9 ...
                & isfinite(minimumErrors) & minimumErrors >= 1 ...
                & minimumErrors == fix(minimumErrors);
            validEstimate = abs(bler-errors./trials) ...
                <= max(1e-12, 0.5./trials);
            stop = upper(strtrim(string(value.StopReason)));
            allowedStops = [ ...
                "CI_AND_MIN_ERRORS_MET"; ...
                "MAX_TB_CENSORED_BOUND_MET"; ...
                "FIXED_TRIAL_BUDGET_COMPLETE"];
            validStop = ismember(stop, allowedStops) ...
                & ~contains(stop, "INCOMPLETE");
            ciStop = stop == "CI_AND_MIN_ERRORS_MET";
            validStop(ciStop) = validStop(ciStop) ...
                & errors(ciStop) >= minimumErrors(ciStop);
            if any(~validCounts | ~validBounds ...
                    | ~validEstimate | ~validStop)
                bad = find(~validCounts | ~validBounds ...
                    | ~validEstimate | ~validStop);
                details = compose( ...
                    "%s/%s[count=%d bounds=%d estimate=%d stop=%d reason=%s]", ...
                    string(value.CampaignID(bad)), ...
                    string(value.OperatingPointID(bad)), ...
                    validCounts(bad),validBounds(bad), ...
                    validEstimate(bad),validStop(bad),stop(bad));
                error("sixgr:pdsch:PDSCHPhasePublisher:BLERStopPolicyMismatch", ...
                    "BLER rows must contain complete count-derived " + ...
                    "estimates, confidence bounds, and canonical " + ...
                    "stop-policy fields. Invalid rows: %s.", ...
                    strjoin(cellstr(details),"; "));
            end
        end

        function validateDigestEvidence(tables)
            independent = tables.pdsch_independent_vector_results;
