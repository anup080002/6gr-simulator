        function value = validateTestSummary(value, requireArtifact)
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                requirePassingTable(value, "pdsch_test_summary");
            required = [ ...
                "TestSuite","Total","Passed","Failed", ...
                "Skipped","Blocked","Status"];
            if ~isequal(string(value.Properties.VariableNames), required)
                error("sixgr:pdsch:PDSCHPhasePublisher:BadTestSummarySchema", ...
                    "PDSCH test summary schema is invalid.");
            end
            names = string(value.TestSuite);
            if numel(unique(names)) ~= height(value)
                error("sixgr:pdsch:PDSCHPhasePublisher:DuplicateTestSuite", ...
                    "PDSCH test summary contains duplicate suite names.");
            end
            catalog = string(sixgr.pdsch. ...
                PDSCHPhaseFocusedTestExecutor.requiredSuiteNames());
            mandatory = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                promptMandatoryTestSuiteNames();
            if numel(unique(catalog)) ~= numel(catalog) ...
                    || numel(mandatory) ~= 48 ...
                    || any(~ismember(mandatory, catalog))
                error("sixgr:pdsch:PDSCHPhasePublisher:SuiteCatalogInvalid", ...
                    "The focused suite catalog must uniquely include all " + ...
                    "48 Prompt-02 mandatory suites.");
            end
            artifactSuite = "testPDSCHArtifactGeneration";
            if requireArtifact
                expectedNames = catalog;
            else
                expectedNames = catalog(catalog ~= artifactSuite);
            end
            if numel(names) ~= numel(expectedNames) ...
                    || ~isempty(setxor(names, expectedNames))
                missing = setdiff(expectedNames, names, "stable");
                unexpected = setdiff(names, expectedNames, "stable");
                error("sixgr:pdsch:PDSCHPhasePublisher:SuiteSetMismatch", ...
                    "PDSCH test summary differs from the exact mandatory " + ...
                    "plus declared-extra suite set. Missing=[%s], " + ...
                    "unexpected=[%s].", ...
                    strjoin(cellstr(missing), ","), ...
                    strjoin(cellstr(unexpected), ","));
            end
            total = double(value.Total);
            passed = double(value.Passed);
            failed = double(value.Failed);
            skipped = double(value.Skipped);
            blocked = double(value.Blocked);
            valid = isfinite(total) & total > 0 ...
                & passed == total & failed == 0 ...
                & skipped == 0 & blocked == 0;
            if any(~valid)
                error("sixgr:pdsch:PDSCHPhasePublisher:BadTestCounts", ...
                    "PDSCH test summary contains invalid observed counts.");
            end
            artifactCount = nnz(names == artifactSuite);
            if (~requireArtifact && artifactCount ~= 0) ...
                    || (requireArtifact && artifactCount ~= 1)
                error("sixgr:pdsch:PDSCHPhasePublisher:ArtifactTestCardinality", ...
                    "Artifact test row cardinality is invalid.");
            end
        end

        function validateExecutionTable(value, label)
            required = [ ...
                "Stage","Source","ExecutionMode","RecordCount", ...
                "PassedCount","FailedCount","DurationSeconds", ...
                "ErrorIdentifier","ErrorMessage","Detail","Status"];
            if ~istable(value) || isempty(value) ...
                    || ~isequal(string(value.Properties.VariableNames), ...
                    required)
                error("sixgr:pdsch:PDSCHPhasePublisher:BadExecutionTable", ...
                    "%s has an invalid execution-evidence schema.", label);
            end
            total = double(value.RecordCount);
            passed = double(value.PassedCount);
            failed = double(value.FailedCount);
            duration = double(value.DurationSeconds);
            status = upper(string(value.Status));
            expectedStatus = repmat("FAIL", height(value), 1);
            expectedStatus(total > 0 & failed == 0 ...
                & passed == total) = "PASS";
            valid = isfinite(total) & total > 0 ...
                & isfinite(passed) & passed >= 0 ...
                & isfinite(failed) & failed >= 0 ...
                & passed + failed == total ...
                & isfinite(duration) & duration >= 0 ...
                & status == expectedStatus;
            if any(~valid)
                error("sixgr:pdsch:PDSCHPhasePublisher:BadExecutionCounts", ...
                    "%s contains inconsistent measured execution rows.", ...
                    label);
            end
        end

        function requirePassingExecution(value, label)
            sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                validateExecutionTable(value, label);
            if any(upper(string(value.Status)) ~= "PASS")
                error("sixgr:pdsch:PDSCHPhasePublisher:ExecutionFailed", ...
                    "%s did not pass.", label);
            end
        end

        function requirePassingTable(value, label)
            if ~istable(value) || isempty(value)
                error("sixgr:pdsch:PDSCHPhasePublisher:EmptyEvidence", ...
                    "%s must contain observed production rows.", label);
            end
            if ~ismember("Status", string(value.Properties.VariableNames))
                error("sixgr:pdsch:PDSCHPhasePublisher:MissingStatus", ...
                    "%s has no Status column.", label);
            end
            if any(upper(strtrim(string(value.Status))) ~= "PASS")
                error("sixgr:pdsch:PDSCHPhasePublisher:NonPassEvidence", ...
                    "%s contains non-passing evidence.", label);
            end
        end

        function validation = validateArtifactResult(validation)
            required = [ ...
                "Passed","CheckStatuses","DurationSeconds", ...
                "VerifierExitCode","CSVCount","PNGCount", ...
                "ErrorIdentifier","ErrorMessage"];
            if ~isstruct(validation) || ~isscalar(validation) ...
                    || any(~isfield(validation, required))
                error("sixgr:pdsch:PDSCHPhasePublisher:BadValidationResult", ...
                    "Artifact validator returned an incomplete result.");
            end
            statuses = sixgr.pdsch.PDSCHPhaseArtifactPublisher. ...
                normalizeStatuses(validation.CheckStatuses);
            observedPass = ~isempty(statuses) ...
                && all(statuses == "PASS") ...
                && double(validation.VerifierExitCode) == 0 ...
                && double(validation.CSVCount) == 20 ...
                && double(validation.PNGCount) == 11;
            if logical(validation.Passed) ~= observedPass
                error("sixgr:pdsch:PDSCHPhasePublisher:ValidationMismatch", ...
                    "Artifact validator aggregate disagrees with its checks.");
            end
            duration = double(validation.DurationSeconds);
            if ~(isscalar(duration) && isfinite(duration) && duration >= 0)
                error("sixgr:pdsch:PDSCHPhasePublisher:BadValidationDuration", ...
                    "Artifact validator duration is invalid.");
            end
        end

        function statuses = normalizeStatuses(raw)
            if islogical(raw)
                statuses = repmat("FAIL", numel(raw), 1);
                statuses(raw(:)) = "PASS";
            elseif isnumeric(raw)
                values = double(raw(:));
                if any(~isfinite(values) | ~ismember(values, [0 1]))
                    error("sixgr:pdsch:PDSCHPhasePublisher:BadStatusValue", ...
                        "Numeric status values must be finite zero or one.");
                end
                statuses = repmat("FAIL", numel(values), 1);
                statuses(values == 1) = "PASS";
            else
                statuses = upper(strtrim(string(raw(:))));
            end
            if isempty(statuses) || any(~ismember(statuses, ["PASS","FAIL"]))
                error("sixgr:pdsch:PDSCHPhasePublisher:BadStatusValue", ...
                    "Execution status values must be nonempty PASS/FAIL.");
            end
        end

