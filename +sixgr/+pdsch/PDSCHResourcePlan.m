classdef PDSCHResourcePlan
    %PDSCHRESOURCEPLAN Immutable PDSCH plan from one ownership map.
    %
    % The planning context is explicit; no PRB, symbol, modulation, layer,
    % or code-block value is inferred from a missing field.

    properties (SetAccess = immutable)
        OwnershipMap
        PRBSet (1,:) double
        SymbolAllocation (1,2) double
        DataIndices (:,1) double
        DataIndicesPerLayer (1,:) cell
        DMRSIndicesPerPort (1,:) cell
        PTRSIndicesPerPort (1,:) cell
        DMRSLogicalPortSet (1,:) double
        PTRSLogicalPortSet (1,:) double
        ReservedUnionIndices (:,1) double
        ExactDataRECount (1,1) double
        NREPerPRB (1,:) double
        LayerCountPerCodeword (1,:) double
        QmPerCodeword (1,:) double
        GPerCodeword (1,:) double
        EPerCodeBlock (1,:) cell
        OverlapCounts (1,1) struct
        ReferenceConfigurationDigest (1,1) string
        IndexBase (1,1) string
    end

    methods
        function obj = PDSCHResourcePlan(ownershipMap, context)
            if ~isa(ownershipMap, ...
                    "sixgr.pdsch.PDSCHResourceOwnershipMap")
                error("sixgr:pdsch:MissingResourceOwnershipMap", ...
                    "PDSCHResourcePlan requires one resolved ownership map.");
            end
            if ~isstruct(context) || ~isscalar(context)
                error("sixgr:pdsch:InvalidResourcePlanningContext", ...
                    "Resource planning context must be a scalar struct.");
            end
            required = [ ...
                "PRBSet","SymbolAllocation","GridNumPRB", ...
                "GridSymbolsPerSlot","BWPStartPRB","AbsoluteSlot", ...
                "UnavailableIndices", ...
                "DMRSIndicesPerPort","PTRSIndicesPerPort", ...
                "DMRSLogicalPortSet","PTRSLogicalPortSet", ...
                "LayerCountPerCodeword","QmPerCodeword", ...
                "CodeBlockCountPerCodeword"];
            missing = required(~isfield(context, required));
            if ~isempty(missing)
                error("sixgr:pdsch:IncompleteResourcePlanningContext", ...
                    "Resource planning context is missing: %s.", ...
                    strjoin(cellstr(missing), ", "));
            end

            prbSet = sixgr.pdsch.PDSCHResourcePlan.indexVector( ...
                context.PRBSet, "InvalidPDSCHPRBSet", false);
            gridNumPRB = sixgr.pdsch.PDSCHResourcePlan.positiveInteger( ...
                context.GridNumPRB, "InvalidPDSCHGridSize");
            gridSymbolsPerSlot = sixgr.pdsch.PDSCHResourcePlan. ...
                positiveInteger(context.GridSymbolsPerSlot, ...
                "InvalidPDSCHGridSymbols");
            if ~ismember(gridSymbolsPerSlot,[12 14])
                error("sixgr:pdsch:InvalidPDSCHGridSymbols", ...
                    "GridSymbolsPerSlot must be 12 or 14.");
            end
            bwpStartPRB = sixgr.pdsch.PDSCHResourcePlan. ...
                nonnegativeInteger(context.BWPStartPRB, ...
                "InvalidPDSCHBWPStart");
            absoluteSlot = sixgr.pdsch.PDSCHResourcePlan. ...
                nonnegativeInteger(context.AbsoluteSlot, ...
                "InvalidPDSCHAbsoluteSlot");
            if any(prbSet >= gridNumPRB)
                error("sixgr:pdsch:PDSCHResourceOutsideBWP", ...
                    "PRBSet extends outside GridNumPRB.");
            end
            symbolAllocation = double(context.SymbolAllocation);
            if ~isvector(symbolAllocation) || numel(symbolAllocation) ~= 2 || ...
                    any(~isfinite(symbolAllocation)) || ...
                    any(symbolAllocation ~= floor(symbolAllocation)) || ...
                    symbolAllocation(1) < 0 || symbolAllocation(2) <= 0
                error("sixgr:pdsch:InvalidPDSCHSymbolAllocation", ...
                    "SymbolAllocation must be explicit zero-based [start length].");
            end
            if sum(symbolAllocation) > gridSymbolsPerSlot
                error("sixgr:pdsch:PDSCHResourceOutsideSlot", ...
                    "SymbolAllocation extends beyond GridSymbolsPerSlot.");
            end

            dmrsByPort = sixgr.pdsch.PDSCHResourcePlan. ...
                validateIndexCells(context.DMRSIndicesPerPort, ...
                "InvalidDMRSIndices");
            ptrsByPort = sixgr.pdsch.PDSCHResourcePlan. ...
                validateIndexCells(context.PTRSIndicesPerPort, ...
                "InvalidPTRSIndices");
            dmrsLogicalPorts = sixgr.pdsch.PDSCHResourcePlan. ...
                logicalPortVector(context.DMRSLogicalPortSet, ...
                numel(dmrsByPort), "InvalidDMRSPortSet");
            ptrsLogicalPorts = sixgr.pdsch.PDSCHResourcePlan. ...
                logicalPortVector(context.PTRSLogicalPortSet, ...
                numel(ptrsByPort), "InvalidPTRSPortSet");
            dmrsUnion = unique([dmrsByPort{:}], "sorted");
            ptrsUnion = unique([ptrsByPort{:}], "sorted");
            allocation = ownershipMap.AllocationIndices(:).';
            nSubcarriers = gridNumPRB * 12;
            allocationSubcarriers = mod(allocation, nSubcarriers);
            allocationSymbols = floor(allocation / nSubcarriers);
            allocationPRBs = floor(allocationSubcarriers / 12);
            scheduledSymbols = symbolAllocation(1) + ...
                (0:(symbolAllocation(2) - 1));
            if any(~ismember(allocationPRBs, prbSet)) ...
                    || any(~ismember(allocationSymbols, scheduledSymbols))
                error("sixgr:pdsch:AllocationOutsideScheduledResources", ...
                    "Ownership-map allocation indices must lie inside the " + ...
                    "explicit PRBSet and SymbolAllocation.");
            end
            [scheduledSubcarrier, scheduledSymbol] = ndgrid( ...
                reshape(prbSet .* 12 + (0:11).', [], 1), ...
                scheduledSymbols);
            expectedAllocation = scheduledSubcarrier(:).' ...
                + nSubcarriers .* scheduledSymbol(:).';
            if numel(allocation) ~= numel(expectedAllocation) ...
                    || ~isequal(sort(allocation), sort(expectedAllocation))
                error("sixgr:pdsch:IncompleteScheduledResourceOwnership", ...
                    "Ownership-map allocation must contain every RE in the " + ...
                    "scheduled PRB/symbol rectangle exactly once.");
            end
            unavailable = sixgr.pdsch.PDSCHResourcePlan.indexVector( ...
                context.UnavailableIndices, "InvalidUnavailableRE", true);
            universe = 0:(gridNumPRB * 12 * gridSymbolsPerSlot - 1);
            resolvedMap = ownershipMap.resolve(struct( ...
                "UniverseIndices", universe, ...
                "UnavailableIndices", unavailable, ...
                "DMRSIndicesPerPort", {dmrsByPort}, ...
                "PTRSIndicesPerPort", {ptrsByPort}, ...
                "DMRSLogicalPortSet", dmrsLogicalPorts, ...
                "PTRSLogicalPortSet", ptrsLogicalPorts, ...
                "GridNumPRB", gridNumPRB, ...
                "GridSymbolsPerSlot", gridSymbolsPerSlot, ...
                "BWPStartPRB", bwpStartPRB, ...
                "AbsoluteSlot", absoluteSlot));
            reserved = resolvedMap.ReservedUnionIndices(:).';
            data = resolvedMap.DataIndices(:).';

            layers = sixgr.pdsch.PDSCHResourcePlan.positiveIntegerVector( ...
                context.LayerCountPerCodeword, ...
                "InvalidLayerCountPerCodeword");
            qms = sixgr.pdsch.PDSCHResourcePlan.positiveIntegerVector( ...
                context.QmPerCodeword, "InvalidQmPerCodeword");
            blocks = sixgr.pdsch.PDSCHResourcePlan.positiveIntegerVector( ...
                context.CodeBlockCountPerCodeword, ...
                "InvalidCodeBlockCountPerCodeword");
            if numel(layers) ~= numel(qms) || numel(layers) ~= numel(blocks)
                error("sixgr:pdsch:CodewordPlanningMismatch", ...
                    "Layer, Qm, and code-block vectors must have one entry per codeword.");
            end
            if sum(layers) < 1 || sum(layers) > 8
                error("sixgr:pdsch:InvalidPDSCHRank", ...
                    "The total PDSCH layer count must be in 1...8.");
            end
            if any(~ismember(qms, [2 4 6 8 10]))
                error("sixgr:pdsch:UnsupportedQm", ...
                    "PDSCH Qm must be one of 2, 4, 6, 8, or 10.");
            end

            dataPerLayer = repmat({data(:)}, 1, sum(layers));
            g = numel(data) .* layers .* qms;
            e = cell(1, numel(g));
            for cw = 1:numel(g)
                quantum = layers(cw) * qms(cw);
                symbolUnits = g(cw) / quantum;
                shortLength = floor(symbolUnits / blocks(cw));
                longCount = mod(symbolUnits, blocks(cw));
                e{cw} = quantum .* [ ...
                    repmat(shortLength, 1, blocks(cw) - longCount), ...
                    repmat(shortLength + 1, 1, longCount)];
                if sum(e{cw}) ~= g(cw)
                    error("sixgr:pdsch:CodeBlockRateMatchLengthMismatch", ...
                        "Per-block E values do not sum to exact G.");
                end
            end

            nREPerPRB = zeros(1, numel(prbSet));
            for i = 1:numel(data)
                subcarrier = mod(data(i), gridNumPRB * 12);
                prb = floor(subcarrier / 12);
                local = find(prbSet == prb, 1);
                if isempty(local)
                    error("sixgr:pdsch:PDSCHResourceOutsideBWP", ...
                        "A data RE maps to a PRB outside the explicit PRBSet.");
                end
                nREPerPRB(local) = nREPerPRB(local) + 1;
            end

            obj.OwnershipMap = resolvedMap;
            obj.PRBSet = prbSet(:).';
            obj.SymbolAllocation = symbolAllocation(:).';
            obj.DataIndices = data(:);
            obj.DataIndicesPerLayer = dataPerLayer;
            obj.DMRSIndicesPerPort = dmrsByPort;
            obj.PTRSIndicesPerPort = ptrsByPort;
            obj.DMRSLogicalPortSet = dmrsLogicalPorts;
            obj.PTRSLogicalPortSet = ptrsLogicalPorts;
            obj.ReservedUnionIndices = reserved(:);
            obj.ExactDataRECount = numel(data);
            obj.NREPerPRB = nREPerPRB;
            obj.LayerCountPerCodeword = layers;
            obj.QmPerCodeword = qms;
            obj.GPerCodeword = g;
            obj.EPerCodeBlock = e;
            obj.OverlapCounts = struct( ...
                "ReservationPairwiseMultiplicity", ...
                resolvedMap.PairwiseOverlapMultiplicity, ...
                "DMRSPTRS", numel(intersect(dmrsUnion, ptrsUnion)), ...
                "DMRSReserved", numel(intersect(dmrsUnion, reserved)), ...
                "PTRSReserved", numel(intersect(ptrsUnion, reserved)), ...
                "ReferenceUnavailable", numel(intersect( ...
                    union(dmrsUnion,ptrsUnion),unavailable)), ...
                "DuplicateAllocation", 0, "DuplicateData", 0);
            if isfield(context,"ReferenceConfigurationDigest")
                digest = string(context.ReferenceConfigurationDigest);
                if ~isscalar(digest)
                    error("sixgr:pdsch:InvalidReferenceConfigurationDigest", ...
                        "ReferenceConfigurationDigest must be a scalar token.");
                end
            else
                digest = "";
            end
            obj.ReferenceConfigurationDigest = digest;
            obj.IndexBase = "zero_based";
        end
    end

    methods (Static, Access = private)
        function cells = validateIndexCells(value, token)
            if ~iscell(value) || ~isrow(value)
                error("sixgr:pdsch:" + string(token), ...
                    "Reference indices must be a row cell array, one cell per port.");
            end
            cells = value;
            for i = 1:numel(cells)
                cells{i} = sixgr.pdsch.PDSCHResourcePlan.indexVector( ...
                    cells{i}, token, true);
            end
        end

        function values = indexVector(values, token, allowEmpty)
            if ~isnumeric(values) || ~isvector(values) || ...
                    (~allowEmpty && isempty(values)) || ...
                    any(~isfinite(values)) || any(values ~= floor(values)) || ...
                    any(values < 0)
                error("sixgr:pdsch:" + string(token), ...
                    "Indices must be zero-based nonnegative integer vectors.");
            end
            values = double(values(:).');
            if numel(unique(values, "stable")) ~= numel(values)
                error("sixgr:pdsch:DuplicateREIndex", ...
                    "Resource-plan index vectors must not contain duplicates.");
            end
        end

        function values = positiveIntegerVector(values, token)
            if ~isnumeric(values) || isempty(values) || ~isvector(values) || ...
                    any(~isfinite(values)) || any(values ~= floor(values)) || ...
                    any(values <= 0)
                error("sixgr:pdsch:" + string(token), ...
                    "The value must be a nonempty vector of positive integers.");
            end
            values = double(values(:).');
        end

        function ports = logicalPortVector(values, count, token)
            if ~isnumeric(values) || ~isvector(values) ...
                    || numel(values) ~= count || any(~isfinite(values)) ...
                    || any(values ~= floor(values)) || any(values < 0) ...
                    || any(values > 23) ...
                    || numel(unique(values,"stable")) ~= numel(values)
                error("sixgr:pdsch:" + string(token), ...
                    "Logical port sets must contain one unique explicit " + ...
                    "port in 0...23 per reference-index cell.");
            end
            ports = double(values(:).');
        end

        function value = positiveInteger(value, token)
            if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value) || ...
                    value ~= floor(value) || value <= 0
                error("sixgr:pdsch:" + string(token), ...
                    "The value must be a positive integer scalar.");
            end
            value = double(value);
        end

        function value = nonnegativeInteger(value, token)
            if ~isnumeric(value) || ~isscalar(value) || ~isfinite(value) ...
                    || value ~= floor(value) || value < 0
                error("sixgr:pdsch:" + string(token), ...
                    "The value must be a nonnegative integer scalar.");
            end
            value = double(value);
        end
    end
end
