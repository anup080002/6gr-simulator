    "RuntimeChannelSeed",double(replay.RuntimeChannelSeed), ...
    "GridNoiseVariance",double(gridNoise), ...
    "SNRdB",double(snr));
end

function row = localCanonicalFadingTrial( ...
        trial,seed,model,rankValue,modulation,tx,rx,bundle,channelEvidence)
bitErrors = 0;
bitsCompared = 0;
for cw = 1:bundle.NumCodewords
    bitErrors = bitErrors + nnz( ...
        rx.TransportBlocks{cw} ~= bundle.TransportBlocks{cw});
    bitsCompared = bitsCompared + numel(bundle.TransportBlocks{cw});
end
% The coverage executor owns both sides of this closed-loop validation
% trial, so use the transmitted modulated symbols as the EVM reference.
% Receiver decision-directed EVM can look excellent after a wrong QAM
% decision and therefore cannot qualify a PHY truth point.
txCodewords = tx.CodewordSymbols;
if ~iscell(txCodewords)
    txCodewords = {txCodewords};
end
rxCodewords = rx.CodewordSymbols;
if ~iscell(rxCodewords)
    rxCodewords = {rxCodewords};
end
symbolErrorEnergy = 0;
symbolReferenceEnergy = 0;
for cw = 1:bundle.NumCodewords
    transmittedSymbols = complex(double(txCodewords{cw}(:)));
    receivedSymbols = complex(double(rxCodewords{cw}(:)));
    if numel(transmittedSymbols) ~= numel(receivedSymbols)
        error("sixgr:pdsch:PDSCHStudyCoverageExecutor:SymbolReferenceShapeMismatch", ...
            "TX and equalized RX codeword symbol counts differ for codeword %d.",cw-1);
    end
    symbolErrorEnergy = symbolErrorEnergy + sum(abs( ...
        receivedSymbols-transmittedSymbols).^2);
    symbolReferenceEnergy = symbolReferenceEnergy + ...
        sum(abs(transmittedSymbols).^2);
end
evm = sqrt(symbolErrorEnergy/max(symbolReferenceEnergy,eps));
decisionDirectedEVM = mean(double(rx.Metrics.EVMPerCodeword),"omitnan");
if isfinite(evm) && evm > 0
    measuredSINR = -20*log10(evm);
elseif evm == 0
    measuredSINR = 300;
else
    measuredSINR = NaN;
end
nmse = double(rx.Metrics.ChannelEstimateNMSE);
if nmse > 0 && isfinite(nmse)
    nmseDB = 10*log10(nmse);
elseif nmse == 0
    nmseDB = -300;
else
    nmseDB = NaN;
end
