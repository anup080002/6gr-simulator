function [lo,hi] = localWilson(errors,trials,confidence)
p = errors/trials;
z = sqrt(2)*erfinv(confidence);
denominator = 1 + z^2/trials;
center = (p + z^2/(2*trials))/denominator;
radius = z/denominator*sqrt( ...
    p*(1-p)/trials + z^2/(4*trials^2));
lo = max(0,center-radius);
hi = min(1,center+radius);
end

