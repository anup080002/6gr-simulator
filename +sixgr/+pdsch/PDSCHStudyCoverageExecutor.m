caseIndex = 0;
for rankValue = 1:8
    for m = 1:numel(mods)
        caseIndex = caseIndex + 1;
        row = localGeneratedCoverageRow( ...
            "NN-" + compose("%02d",caseIndex), ...
            rankValue, mods(m), "AWGN", mod(rankValue,2) == 0);
        bundle = localBuildStrictBundle( ...
            row, seeds(1 + mod(caseIndex-1,numel(seeds))), false, []);
