function waveform = localImpairedWaveform(waveform,seed,snr)
waveform = localAWGNWaveform(waveform,seed,snr);
waveform = localPhaseRamp(waveform,seed,2);
end

function waveform = localAWGNWaveform(waveform,seed,snr)
rng(double(seed),"twister");
power = mean(abs(waveform(:)).^2);
variance = power/10^(double(snr)/10);
noise = sqrt(variance/2)*complex( ...
    randn(size(waveform)),randn(size(waveform)));
waveform = waveform + noise;
end

function waveform = localPhaseRamp(waveform,seed,maxDegrees)
rng(double(seed)+991,"twister");
n = size(waveform,1);
phase = linspace(0,maxDegrees*pi/180,n).' ...
    + .05*pi/180*cumsum(randn(n,1))/sqrt(max(n,1));
waveform = waveform .* exp(1j*phase);
end

function variance = localGridNoiseVariance(tx,waveform,snr)
signalPower = mean(abs(tx.Waveform(:)).^2);
timeVariance = signalPower/10^(double(snr)/10);
variance = timeVariance * ...
    double(tx.OFDMInfo.SampleToGridNoiseVarianceGain);
if ~(isfinite(variance) && variance >= 0)
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:InvalidNoiseVariance", ...
        "Unable to resolve finite grid-domain noise variance.");
end
if isempty(waveform) %#ok<UNRCH>
    variance = variance;
end
end

