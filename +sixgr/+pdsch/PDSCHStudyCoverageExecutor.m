end
K = carrier.NSizeGrid*12;
ports = unique(double(sub(:,3)),"stable");
if numel(ports) ~= size(values,2)
    if size(values,2) == 1
        ports = ports(1);
    else
        error("sixgr:pdsch:PDSCHStudyCoverageExecutor:PTRSShapeMismatch", ...
            "PT-RS port index/symbol dimensions differ.");
    end
end
for i = 1:numel(ports)
    layer = ports(i);
    if layer < 0 || layer >= rankValue
        error("sixgr:pdsch:PDSCHStudyCoverageExecutor:PTRSPortOutsideRank", ...
            "PT-RS layer-port index lies outside the scheduled rank.");
    end
    mask = double(sub(:,3)) == layer;
    indices{layer+1} = double( ...
        sub(mask,1) + K*sub(mask,2)).';
    symbols{layer+1} = complex(values(:,min(i,size(values,2))));
end
end

function allocation = localAllocationIndices(nPRB,prbSet,symbolAllocation)
subcarriers = reshape((12*prbSet(:).' + (0:11).'),1,[]);
symbols = symbolAllocation(1) + (0:symbolAllocation(2)-1);
[k,l] = ndgrid(subcarriers,symbols);
allocation = sort(double(k(:) + 12*nPRB*l(:))).';
end

function precoder = localPrecoder(mode,rankValue,prbSet,symbolAllocation)
mode = lower(strtrim(string(mode)));
symbols = symbolAllocation(1) + (0:symbolAllocation(2)-1);
if startsWith(mode,"wideband")
    prgSize = 0;
    nPRG = 1;
else
    prgSize = 2;
    nPRG = ceil(numel(prbSet)/prgSize);
end
W = complex(zeros(rankValue,rankValue,nPRG,1));
F = localDFT(rankValue);
for p = 1:nPRG
    permutation = circshift(1:rankValue,p-1);
    W(:,:,p,1) = diag(exp(1j*(0:rankValue-1).'*p/11)) ...
        * F(:,permutation);
end
codebook = "";
if contains(mode,"codebook") && ~contains(mode,"noncodebook")
    codebook = "coverage_explicit_matrix_codebook";
end
spec = struct( ...
    "Mode",mode,"NPorts",rankValue,"NLayers",rankValue, ...
    "NPRG",nPRG,"NSymbolGroups",1,"PRGSize",prgSize, ...
    "PRBSet",prbSet,"ScheduledSymbols",symbols, ...
    "SymbolGroupMap",zeros(1,numel(symbols)), ...
    "W",W,"MatrixSource","coverage_executor_explicit_matrix", ...
    "CodebookIdentifier",codebook, ...
    "NormalizationConvention","semi_unitary", ...
    "NormalizationTolerance",2e-12);
precoder = sixgr.pdsch.PDSCHPrecoderBundle(spec);
end

function F = localDFT(order)
row = (0:order-1).';
column = 0:order-1;
F = exp(-1j*2*pi*row*column/order)/sqrt(order);
end

