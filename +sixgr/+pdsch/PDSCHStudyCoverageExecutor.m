        dmrsConfigType,dmrsLength,dmrsAdditionalPosition, ...
        dmrsMultiplexing,dmrsPorts,ptrsEnabled,reservationMode,precodingMode, ...
        rv,prbSet,mcsIndex,executionLabel)
