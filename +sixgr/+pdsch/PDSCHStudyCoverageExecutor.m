function [indices,symbols] = localToolboxDMRS(carrier,pdsch,rankValue)
sub = nrPDSCHDMRSIndices(carrier,pdsch, ...
    "IndexStyle","subscript","IndexBase","0based");
values = nrPDSCHDMRS(carrier,pdsch);
if isempty(sub) || size(values,2) ~= rankValue
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:DMRSMaterializationFailed", ...
        "Toolbox did not materialize one DM-RS stream per layer.");
end
K = carrier.NSizeGrid*12;
indices = cell(1,rankValue);
symbols = cell(1,rankValue);
for layer = 0:(rankValue-1)
    mask = double(sub(:,3)) == layer;
    indices{layer+1} = double( ...
        sub(mask,1) + K*sub(mask,2)).';
    symbols{layer+1} = complex(values(:,layer+1));
    if numel(indices{layer+1}) ~= numel(symbols{layer+1})
        error("sixgr:pdsch:PDSCHStudyCoverageExecutor:DMRSShapeMismatch", ...
            "DM-RS index/symbol counts differ for layer %d.",layer);
    end
end
end

