function [outcome, negative, metricRows, truth] = ...
        localExecuteDeclaredKind(row, kind, seed, truthTrials)
expected = "PASS";
actual = "FAIL";
identifier = "";
detail = "";
txExecuted = false;
rxExecuted = false;
crcPass = false;
channelScope = "pre_tx_validation_only";
executionBackend = "not_executed";
negative = localEmptyNegativeRow();
metricRows = repmat(localEmptyReceiverMetricRow(),0,1);
truth = [];
isFading = any(startsWith( ...
    upper(string(row.ChannelModel)),["TDL-","CDL-"]));
try
    switch kind
        case "positive"
            executionBackend = "canonical_pdsch_tx_channel_rx";
            if isFading
                truth = localRunRowTruth( ...
                    row,kind,seed,truthTrials,false);
                txExecuted = true;
                rxExecuted = true;
                crcPass = logical(truth.TBErrors == 0);
                localRequire(truth.Passed && crcPass, ...
                    "sixgr:pdsch:PDSCHStudyCoverageExecutor:FadingPositiveFailed", ...
                    "Canonical declared fading positive point did not decode.");
                channelScope = truth.ChannelEstimateScope;
                detail = "single_canonical_fading_tx_channel_rx_execution";
                metricRows = localTruthMetricRows(row.CaseID,truth);
            else
                bundle = localBuildStrictBundle(row, seed, false, []);
                tx = sixgr.pdsch.PDSCHTransmitter( ...
                    bundle.TransportBlocks, bundle.Assignment, ...
                    bundle.ResourcePlan, bundle.Carrier, ...
                    bundle.ReferenceConfig, ...
                    "PrecoderBundle", bundle.PrecoderBundle);
                txExecuted = true;
                rxExecuted = true;
                rx = localStrictReceive(tx.Waveform, bundle, 0, ...
                    "CodingPlans",tx.CodingPlans);
                crcPass = logical(rx.CRCPass);
                localRequire(crcPass, ...
                    "sixgr:pdsch:PDSCHStudyCoverageExecutor:PositiveCRCFailure", ...
                    "Exact positive round trip failed TB CRC.");
                detail = "exact_explicit_awgn_tx_rx_round_trip";
                channelScope = "explicit_awgn_receiver_contract";
                metricRows = localStrictMetricRows( ...
                    row.CaseID,120,"AWGN",bundle,rx);
            end
        case "no_signal"
            executionBackend = "canonical_receiver_input_validation";
            bundle = localBuildStrictBundle(row, seed, false, []);
            rxExecuted = true;
            observed = localCaptureIdentifier(@() ...
                localStrictReceive( ...
                complex(zeros(16,bundle.Rank)), bundle, 0));
            identifier = observed;
            localRequire(observed == ...
                "sixgr:pdsch:PDSCHReceiver:NoReceivedSignal", ...
                "sixgr:pdsch:PDSCHStudyCoverageExecutor:UnexpectedNoSignalOutcome", ...
                "No-signal receiver rejection had an unexpected identifier.");
            negative = localNegativeRow(row.CaseID, kind, ...
                "sixgr:pdsch:PDSCHReceiver:NoReceivedSignal", observed);
            detail = "typed_all_zero_receiver_rejection";
            channelScope = "receiver_input_validation_before_ofdm";
        case "wrong_rnti"
            executionBackend = "canonical_assignment_validation";
            [expectedId, actualId] = localWrongRNTIPreTXCheck(row);
            identifier = actualId;
            negative = localNegativeRow( ...
                row.CaseID, kind, expectedId, actualId);
            detail = "typed_dci_rnti_rejection_before_tx";
        case "wrong_dmrs"
            executionBackend = "canonical_dmrs_configuration_validation";
            [expectedId, actualId] = localWrongDMRSPreTXCheck(row);
            identifier = actualId;
            negative = localNegativeRow( ...
                row.CaseID, kind, expectedId, actualId);
            detail = "typed_invalid_dmrs_rejection_before_tx";
        case "wrong_rv"
            executionBackend = "canonical_dlsch_coding_plan_validation";
            bundle = localBuildStrictBundle(row, seed, false, []);
            [expectedId, actualId] = ...
                localWrongRVPreTXCheck(bundle);
            identifier = actualId;
            negative = localNegativeRow( ...
                row.CaseID, kind, expectedId, actualId);
            detail = "typed_invalid_rv_rejection_before_tx";
        case "reserved_re"
            executionBackend = "canonical_pdsch_tx_channel_rx";
            if isFading
                truth = localRunRowTruth( ...
                    row,kind,seed,truthTrials,false);
                txExecuted = true;
                rxExecuted = true;
                crcPass = logical(truth.TBErrors == 0);
                localRequire(truth.Passed && crcPass && ...
                    truth.ReservationApplied && truth.ReservationReducedG, ...
                    "sixgr:pdsch:PDSCHStudyCoverageExecutor:FadingReservedFailed", ...
                    "Declared fading reserved-RE point did not apply a " + ...
                    "real reservation, reduce G, and decode canonically.");
                channelScope = truth.ChannelEstimateScope;
                detail = ...
                    "single_canonical_fading_reserved_tx_channel_rx_execution";
            else
                reserved = localBuildStrictBundle(row, seed, true, []);
                txReserved = sixgr.pdsch.PDSCHTransmitter( ...
                    reserved.TransportBlocks, reserved.Assignment, ...
                    reserved.ResourcePlan, reserved.Carrier, ...
                    reserved.ReferenceConfig, ...
                    "PrecoderBundle", reserved.PrecoderBundle);
                txExecuted = true;
                rxExecuted = true;
                rx = localStrictReceive( ...
                    txReserved.Waveform,reserved,0, ...
                    "CodingPlans",txReserved.CodingPlans);
                crcPass = logical(rx.CRCPass);
                baseline = localBuildStrictBundle(row, seed, false, []);
                localRequire(crcPass && ...
                    reserved.ResourcePlan.ExactDataRECount < ...
                    baseline.ResourcePlan.ExactDataRECount, ...
                    "sixgr:pdsch:PDSCHStudyCoverageExecutor:ReservedRENotApplied", ...
                    "Legal reserved RE did not reduce G and decode exactly.");
                detail = "legal_rate_match_reservation_applied_before_coding";
                channelScope = "explicit_awgn_receiver_contract";
            end
        case "impairment"
            executionBackend = "canonical_pdsch_tx_channel_rx";
            if isFading
                truth = localRunRowTruth( ...
                    row,kind,seed,truthTrials,true);
                txExecuted = true;
                rxExecuted = true;
                crcPass = logical(truth.TBErrors == 0);
                localRequire(truth.Passed, ...
                    "sixgr:pdsch:PDSCHStudyCoverageExecutor:FadingImpairmentFailed", ...
                    "Declared fading impairment point lacked canonical RX evidence.");
                channelScope = truth.ChannelEstimateScope;
                detail = ...
                    "single_canonical_fading_phase_noise_tx_channel_rx_execution";
            else
                bundle = localBuildStrictBundle(row, seed, false, []);
                tx = sixgr.pdsch.PDSCHTransmitter( ...
                    bundle.TransportBlocks, bundle.Assignment, ...
                    bundle.ResourcePlan, bundle.Carrier, ...
                    bundle.ReferenceConfig, ...
                    "PrecoderBundle", bundle.PrecoderBundle);
                txExecuted = true;
                rxExecuted = true;
                waveform = localImpairedWaveform(tx.Waveform, seed, 32);
                gridNoise = localGridNoiseVariance(tx, waveform, 32);
                rx = localStrictReceive(waveform,bundle,gridNoise, ...
                    "CodingPlans",tx.CodingPlans);
                crcPass = logical(rx.CRCPass);
                localRequire(all(isfinite( ...
                    rx.Metrics.MeasuredPostEqualizationSINRdBPerLayer)), ...
                    "sixgr:pdsch:PDSCHStudyCoverageExecutor:NonfiniteImpairmentMetrics", ...
                    "Impaired production receiver emitted nonfinite SINR.");
                detail = ...
                    "deterministic_phase_ramp_plus_awgn_receiver_execution";
                channelScope = "explicit_awgn_receiver_contract";
            end
        otherwise
            error("sixgr:pdsch:PDSCHStudyCoverageExecutor:UnknownTestKind", ...
                "Unsupported declared test kind '%s'.", kind);
    end
    actual = "PASS";
catch ME
    if strlength(identifier) == 0
        identifier = string(ME.identifier);
    end
    detail = string(ME.message);
end

status = "FAIL";
if actual == expected
    status = "PASS";
end
outcome = struct( ...
    "CaseID", string(row.CaseID), ...
    "TestKind", string(kind), ...
    "Rank", double(row.Rank), ...
    "Modulation", string(row.Modulation), ...
    "ChannelModel", string(row.ChannelModel), ...
    "ProductionTXExecuted", logical(txExecuted), ...
    "ProductionRXExecuted", logical(rxExecuted), ...
    "ExpectedStatus", expected, ...
    "ActualStatus", actual, ...
    "ErrorIdentifier", string(identifier), ...
    "Status", status, ...
    "ExecutionBackend",string(executionBackend), ...
    "ChannelEstimateScope", string(channelScope), ...
    "ReceiverCRCPass", logical(crcPass), ...
    "EvidenceDetail", string(detail));
end

