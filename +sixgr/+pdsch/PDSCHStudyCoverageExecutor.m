        function probe = runReceiverTruthPoint(channelModel, varargin)
            %RUNRECEIVERTRUTHPOINT Execute one concrete fading truth point.
            %
            % This public bounded probe exists for focused TDL/CDL receiver
            % tests. It executes the canonical explicit TX/RX chain and
            % rejects scalar/fallback/proxy channel-estimation evidence.
            ip = inputParser;
            ip.FunctionName = ...
                "sixgr.pdsch.PDSCHStudyCoverageExecutor.runReceiverTruthPoint";
            ip.addParameter("Rank", 2, ...
                @(x) isnumeric(x) && isscalar(x) && x >= 1 && x <= 8);
            ip.addParameter("Modulation", "16QAM", ...
                @(x) ischar(x) || (isstring(x) && isscalar(x)));
            ip.addParameter("SNRdB", 35, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x));
            ip.addParameter("Seed", 11, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x));
            ip.addParameter("NumTrials", 1, ...
                @(x) isnumeric(x) && isscalar(x) && x >= 1);
            ip.addParameter("EnablePhaseNoise", false, ...
                @(x) islogical(x) && isscalar(x));
            ip.addParameter("NumerologyKHz", 30, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x));
            ip.addParameter("MappingType", "A", ...
                @(x) any(upper(string(x)) == ["A","B"]));
            ip.addParameter("DMRSConfigurationType", 1, ...
                @(x) isnumeric(x) && isscalar(x) && any(x == [1 2]));
            ip.addParameter("DMRSLength", 1, ...
                @(x) isnumeric(x) && isscalar(x) && any(x == [1 2]));
            ip.addParameter("DMRSAdditionalPosition", 1, ...
                @(x) isnumeric(x) && isscalar(x) && any(x == 0:3));
            ip.addParameter("DMRSMultiplexing", "basic", ...
                @(x) any(lower(string(x)) == ["basic","enhanced"]));
            ip.addParameter("DMRSPortSet", [], ...
                @(x) isempty(x) || (isnumeric(x) && isvector(x)));
            ip.addParameter("PTRSEnabled", false, ...
                @(x) islogical(x) && isscalar(x));
            ip.addParameter("ApplyReservation", false, ...
                @(x) islogical(x) && isscalar(x));
            ip.addParameter("ReservationMode", "", ...
                @(x) any(lower(string(x)) == ...
                    ["","none","single","overlapping"]));
            ip.addParameter("PrecodingMode", "wideband_codebook", ...
                @(x) ischar(x) || (isstring(x) && isscalar(x)));
            ip.addParameter("RV", 0, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x) ...
                    && x == fix(x) && any(x == 0:3));
            ip.addParameter("MCSIndex", [], ...
                @(x) isempty(x) || (isnumeric(x) && isscalar(x) ...
                    && isfinite(x) && x == fix(x) && x >= 0));
            ip.addParameter("PRBSet", 0:5, ...
                @(x) isnumeric(x) && isvector(x) && ~isempty(x) ...
                    && all(isfinite(x)) && all(x == fix(x)) && all(x >= 0));
            ip.addParameter("ExecutionLabel", "receiver_probe", ...
                @(x) ischar(x) || (isstring(x) && isscalar(x)));
            ip.parse(varargin{:});
            opt = ip.Results;

            ports = double(opt.DMRSPortSet(:).');
            if isempty(ports)
                ports = 0:(round(double(opt.Rank))-1);
            end
            prbSet = double(opt.PRBSet(:).');
            if numel(unique(prbSet,"stable")) ~= numel(prbSet)
                error("sixgr:pdsch:PDSCHStudyCoverageExecutor:DuplicatePRBSet", ...
                    "PRBSet must not contain duplicate carrier-relative PRBs.");
            end
            reservationMode = lower(string(opt.ReservationMode));
            if strlength(reservationMode) == 0
                reservationMode = string(ternary( ...
                    logical(opt.ApplyReservation),"single","none"));
            end
            probe = localRunTruthPointCached( ...
                upper(strtrim(string(channelModel))), ...
                round(double(opt.Rank)), ...
                upper(strtrim(string(opt.Modulation))), ...
                double(opt.SNRdB), round(double(opt.Seed)), ...
                round(double(opt.NumTrials)), ...
                logical(opt.EnablePhaseNoise), ...
                double(opt.NumerologyKHz), ...
                upper(string(opt.MappingType)), ...
                double(opt.DMRSConfigurationType), ...
                double(opt.DMRSLength), ...
                double(opt.DMRSAdditionalPosition), ...
                lower(string(opt.DMRSMultiplexing)), ...
                ports, logical(opt.PTRSEnabled), ...
                reservationMode, ...
                lower(string(opt.PrecodingMode)), double(opt.RV), ...
                prbSet, double(opt.MCSIndex), ...
                string(opt.ExecutionLabel));
        end

        function proof = pairCoverageProof(vectorRoot, varargin)
            %PAIRCOVERAGEPROOF Prove constrained pair coverage without PHY work.
            ip = inputParser;
            ip.FunctionName = ...
                "sixgr.pdsch.PDSCHStudyCoverageExecutor.pairCoverageProof";
            ip.addParameter("SelectedCaseCount", Inf, ...
                @(x) isnumeric(x) && isscalar(x) && x >= 1);
            ip.addParameter("FailOnMissing", true, ...
                @(x) islogical(x) && isscalar(x));
            ip.parse(varargin{:});
            localReadCoverageMatrix(fullfile( ...
                string(vectorRoot),"pdsch_declared_coverage_matrix.csv"));
            [generated,required,factors] = localGeneratePairwiseDesign();
            count = min(height(generated),floor(double( ...
                ip.Results.SelectedCaseCount)));
            proof = localPairSelectionProof( ...
                generated(1:count,:),required,factors);
            if logical(ip.Results.FailOnMissing) ...
                    && proof.MissingPairCount ~= 0
                error( ...
                    "sixgr:pdsch:PDSCHStudyCoverageExecutor:PairCoverageIncomplete", ...
                    "Selected rows cover %d/%d feasible pairs; %d are missing.", ...
                    proof.CoveredPairCount,proof.RequiredPairCount, ...
                    proof.MissingPairCount);
            end
        end
    end
end

function matrix = localReadCoverageMatrix(path)
if ~isfile(path)
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:CoverageMatrixMissing", ...
        "Declared coverage matrix is missing: %s.", path);
end
opts = detectImportOptions(path, ...
    "Delimiter", ",", "VariableNamingRule", "preserve");
textNames = ["CaseID","MappingType","DMRSMultiplexing", ...
    "DMRSPortSet","Modulation","RVSequence","PrecodingMode", ...
    "ChannelModel","RequiredTestKinds","ExpectedStatus"];
opts = setvartype(opts, intersect(opts.VariableNames, ...
    cellstr(textNames), "stable"), "string");
matrix = readtable(path, opts);
required = [ ...
    "CaseID","Rank","NumCodewords","MappingType", ...
    "DMRSConfigurationType","DMRSLength","DMRSAdditionalPosition", ...
    "DMRSMultiplexing","DMRSPortSet","PTRSEnabled","Modulation", ...
    "RVSequence","PrecodingMode","ChannelModel","NumerologyKHz", ...
    "RequiredTestKinds","ExpectedStatus"];
if ~isequal(string(matrix.Properties.VariableNames), required)
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:CoverageMatrixSchemaMismatch", ...
        "Declared coverage matrix does not match the frozen schema.");
end
if height(matrix) < 1 || numel(unique(matrix.CaseID)) ~= height(matrix)
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:CoverageMatrixInvalid", ...
        "Declared coverage rows require nonempty unique CaseID values.");
end
mandatoryKinds = [ ...
    "positive","no_signal","wrong_rnti","wrong_dmrs", ...
    "wrong_rv","reserved_re","impairment"];
for i = 1:height(matrix)
    kinds = split(lower(matrix.RequiredTestKinds(i)), "|");
    if ~isequal(kinds(:).', mandatoryKinds)
        error("sixgr:pdsch:PDSCHStudyCoverageExecutor:CoverageKindsMismatch", ...
            "Case %s does not contain the exact mandatory test kinds.", ...
            matrix.CaseID(i));
    end
    if upper(strtrim(matrix.ExpectedStatus(i))) ~= "PASS"
        error("sixgr:pdsch:PDSCHStudyCoverageExecutor:CoverageExpectationInvalid", ...
            "Case %s must have ExpectedStatus=PASS.", matrix.CaseID(i));
    end
end
end

function [results, negatives, metrics, truthRows] = ...
        localRunDeclared(matrix, seeds, truthTrials)
rows = repmat(localEmptyDeclaredRow(), 0, 1);
negativeRows = repmat(localEmptyNegativeRow(), 0, 1);
metricRows = repmat(localEmptyReceiverMetricRow(), 0, 1);
truthRows = localEmptyFadingAnchorTable();
for i = 1:height(matrix)
    row = matrix(i, :);
    seed = seeds(1 + mod(i - 1, numel(seeds)));
    kinds = split(lower(row.RequiredTestKinds), "|");
    for k = 1:numel(kinds)
        [outcome, negative, producedMetrics, truth] = ...
            localExecuteDeclaredKind( ...
            row, kinds(k), seed, truthTrials);
        rows(end+1,1) = outcome; %#ok<AGROW>
        if strlength(negative.CaseID) > 0
            negativeRows(end+1,1) = negative; %#ok<AGROW>
        end
        if ~isempty(producedMetrics)
            metricRows = [metricRows; producedMetrics]; %#ok<AGROW>
        end
        if ~isempty(truth)
            truthRows = [truthRows; localTruthAnchorRow(truth)]; %#ok<AGROW>
        end
    end
end
results = struct2table(rows);
negatives = struct2table(negativeRows);
metrics = struct2table(metricRows);
end

