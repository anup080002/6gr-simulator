classdef PDSCHStudyCoverageExecutor
    %PDSCHCOVERAGEEXECUTOR Bounded, production-backed Prompt-02 coverage.
    %
    % E = sixgr.pdsch.PDSCHStudyCoverageExecutor.run( ...
    %     "VectorRoot", vectorRoot, ...
    %     "SeedList", [11 23 47 89], ...
    %     "ConfidenceLevel", 0.95, ...
    %     "Strict", true)
    %
    % The returned scalar struct has these stable fields:
    %   Passed                   - fail-closed aggregate result
    %   DeclaredCoverageResults  - one row per declared case/test kind
    %   PairwiseCases            - deterministic factor-covering executions
    %   NoNoiseRoundTrip         - rank/modulation exact round trips
    %   ReceiverMetrics          - exact pdsch_receiver_metrics.csv schema
    %   BLERCurve                - exact pdsch_bler_curve.csv schema
    %   NegativeTests            - exact pdsch_negative_tests.csv schema
    %   TestSummary              - exact pdsch_test_summary.csv schema
    %   FadingTruthAnchors       - canonical TDL/CDL execution evidence
    %
    % Every TDL/CDL row is one end-to-end execution of PDSCHTransmitter,
    % a concrete 38.901 Toolbox channel, and PDSCHReceiver. The receiver
    % estimates the effective layer channel from DM-RS per resource. No
    % AWGN result, legacy link-chain result, proxy, or fallback is spliced
    % into a fading row.

    methods (Static)
        function evidence = run(varargin)
            ip = inputParser;
            ip.FunctionName = "sixgr.pdsch.PDSCHStudyCoverageExecutor.run";
            ip.addParameter("VectorRoot", "", ...
                @(x) ischar(x) || (isstring(x) && isscalar(x)));
            ip.addParameter("SeedList", [11 23 47 89], ...
                @(x) isnumeric(x) && isvector(x) && ~isempty(x));
            ip.addParameter("ConfidenceLevel", 0.95, ...
                @(x) isnumeric(x) && isscalar(x) && x > 0 && x < 1);
            ip.addParameter("Strict", true, ...
                @(x) islogical(x) && isscalar(x));
            ip.addParameter("RunDeclaredCoverage", true, ...
                @(x) islogical(x) && isscalar(x));
            ip.addParameter("RunPairwise", true, ...
                @(x) islogical(x) && isscalar(x));
            ip.addParameter("RunNoNoise", true, ...
                @(x) islogical(x) && isscalar(x));
            ip.addParameter("RunBLER", true, ...
                @(x) islogical(x) && isscalar(x));
            ip.addParameter("CoverageCaseIDs", strings(0,1), ...
                @(x) ischar(x) || isstring(x) || iscellstr(x)); %#ok<ISCLSTR>
            ip.addParameter("PairwiseCaseLimit", Inf, ...
                @(x) isnumeric(x) && isscalar(x) && x >= 1);
            ip.addParameter("TruthAnchorTrials", 1, ...
                @(x) isnumeric(x) && isscalar(x) && x >= 1);
            ip.addParameter("BLERMinimumTrials", 4, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x >= 1);
            ip.addParameter("BLERMaximumTrials", 8, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x >= 1);
            ip.addParameter("BLERMinimumErrors", 1, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x >= 1);
            ip.addParameter("BLERCIHalfWidthTarget", 0.35, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x) ...
                    && x > 0 && x < 1);
            ip.addParameter("BLERCensoredUpperBoundTarget", 0.35, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x) ...
                    && x > 0 && x < 1);
            ip.addParameter("BLERCampaignIDs", strings(0,1), ...
                @(x) ischar(x) || isstring(x) || iscellstr(x)); %#ok<ISCLSTR>
            ip.addParameter("BLEROperatingPointLimit", 4, ...
                @(x) isnumeric(x) && isscalar(x) && isfinite(x) && x >= 1);
            ip.addParameter("BLEROperatingPointIndices", [], ...
                @(x) isempty(x) || (isnumeric(x) && isvector(x) ...
                    && all(isfinite(x)) && all(x == fix(x)) && all(x >= 1)));
            ip.parse(varargin{:});
            opt = ip.Results;

            vectorRoot = string(opt.VectorRoot);
            if strlength(strtrim(vectorRoot)) == 0
                error("sixgr:pdsch:PDSCHStudyCoverageExecutor:MissingVectorRoot", ...
                    "VectorRoot must identify the frozen PDSCH vector pack.");
            end
            matrixPath = fullfile(vectorRoot, ...
                "pdsch_declared_coverage_matrix.csv");
            matrix = localReadCoverageMatrix(matrixPath);
            selected = string(opt.CoverageCaseIDs);
            selected = selected(:);
            selected = selected(strlength(strtrim(selected)) > 0);
            if ~isempty(selected)
                unknown = setdiff(selected, matrix.CaseID, "stable");
                if ~isempty(unknown)
                    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:UnknownCaseID", ...
                        "Unknown declared coverage case(s): %s.", ...
                        strjoin(cellstr(unknown), ", "));
                end
                matrix = matrix(ismember(matrix.CaseID, selected), :);
            end

            seeds = double(opt.SeedList(:).');
            if any(~isfinite(seeds) | seeds ~= fix(seeds))
                error("sixgr:pdsch:PDSCHStudyCoverageExecutor:InvalidSeedList", ...
                    "SeedList must contain finite integer values.");
            end
            minBLERTrials = floor(double(opt.BLERMinimumTrials));
            maxBLERTrials = floor(double(opt.BLERMaximumTrials));
            minBLERErrors = floor(double(opt.BLERMinimumErrors));
            if maxBLERTrials < minBLERTrials
                error("sixgr:pdsch:PDSCHStudyCoverageExecutor:InvalidBLERTrialBudget", ...
                    "BLERMaximumTrials must be at least BLERMinimumTrials.");
            end
            if minBLERErrors > maxBLERTrials
                error("sixgr:pdsch:PDSCHStudyCoverageExecutor:InvalidBLERErrorTarget", ...
                    "BLERMinimumErrors cannot exceed BLERMaximumTrials.");
            end

            anchors = localEmptyFadingAnchorTable();
            declared = localEmptyDeclaredTable();
            negatives = localEmptyNegativeTable();
            declaredMetrics = localEmptyReceiverMetricTable();
            if logical(opt.RunDeclaredCoverage)
                [declared, negatives, declaredMetrics, anchors] = ...
                    localRunDeclared(matrix, seeds, ...
                    double(opt.TruthAnchorTrials));
                integrationNegatives = ...
                    localRunIntegrationNegatives(matrix, seeds);
                negatives = [negatives; integrationNegatives];
            end

            pairwise = localEmptyPairwiseTable();
            if logical(opt.RunPairwise)
                [pairwise, pairwiseTruth] = localRunPairwise( ...
                    matrix, seeds, double(opt.PairwiseCaseLimit), ...
                    double(opt.TruthAnchorTrials));
                anchors = [anchors; pairwiseTruth]; %#ok<AGROW>
            end

            noNoise = localEmptyNoNoiseTable();
            noNoiseMetrics = localEmptyReceiverMetricTable();
            if logical(opt.RunNoNoise)
                [noNoise, noNoiseMetrics] = ...
                    localRunNoNoise(seeds);
            end
            receiverMetrics = [declaredMetrics; noNoiseMetrics];

            bler = localEmptyBLERTable();
            if logical(opt.RunBLER)
                bler = localRunBLER(seeds, ...
                    double(opt.ConfidenceLevel), minBLERTrials, ...
                    maxBLERTrials, minBLERErrors, ...
                    double(opt.BLERCIHalfWidthTarget), ...
                    double(opt.BLERCensoredUpperBoundTarget), ...
                    string(opt.BLERCampaignIDs), ...
                    floor(double(opt.BLEROperatingPointLimit)), ...
                    double(opt.BLEROperatingPointIndices(:).'));
            end

            summary = localBuildSummary( ...
                declared, pairwise, noNoise, anchors, bler, ...
                negatives, opt);
            pass = all(upper(string(summary.Status)) == "PASS");
            if ~isempty(declared)
                pass = pass && all(upper(declared.Status) == "PASS");
            end
            if ~isempty(pairwise)
                pass = pass && all(upper(pairwise.Status) == "PASS");
            end
            if ~isempty(noNoise)
                pass = pass && all(upper(noNoise.Status) == "PASS");
            end
            if ~isempty(anchors)
                pass = pass && all(upper(anchors.Status) == "PASS");
            end
            if ~isempty(bler)
                pass = pass && all(upper(bler.Status) == "PASS");
            end
            if ~isempty(negatives)
                pass = pass && all(upper(negatives.Status) == "PASS");
            end

            evidence = struct( ...
                "ContractVersion", "PDSCHStudyCoverageExecutor/v1", ...
                "Passed", logical(pass), ...
                "VectorRoot", vectorRoot, ...
                "SeedList", seeds, ...
                "ConfidenceLevel", double(opt.ConfidenceLevel), ...
                "Strict", logical(opt.Strict), ...
                "DeclaredCoverageResults", declared, ...
                "PairwiseCases", pairwise, ...
                "NoNoiseRoundTrip", noNoise, ...
                "ReceiverMetrics", receiverMetrics, ...
                "BLERCurve", bler, ...
                "NegativeTests", negatives, ...
                "TestSummary", summary, ...
                "FadingTruthAnchors", anchors);

            if logical(opt.Strict) && ~evidence.Passed
                failed = summary(upper(string(summary.Status)) ~= "PASS", :);
                error("sixgr:pdsch:PDSCHStudyCoverageExecutor:CoverageFailed", ...
                    "Production PDSCH coverage failed in suite(s): %s.", ...
                    strjoin(cellstr(string(failed.TestSuite)), ", "));
            end
        end

