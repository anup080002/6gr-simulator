function evidence = localStrictReservationEvidence( ...
        baselinePlan,reservedPlan,reservationMode)
reservationMode = lower(string(reservationMode));
requested = reservationMode ~= "none";
baselineG = sum(double(baselinePlan.GPerCodeword));
reservedG = sum(double(reservedPlan.GPerCodeword));
reservedCount = numel(reservedPlan.OwnershipMap.ReservedUnionIndices);
sources = string(fieldnames( ...
    reservedPlan.OwnershipMap.ReservationSources));
active = strings(0,1);
for idx = 1:numel(sources)
    if ~isempty(reservedPlan.OwnershipMap. ...
            ReservationSources.(sources(idx)))
        active(end+1,1) = sources(idx); %#ok<AGROW>
    end
end
if isempty(active)
    source = "not_requested";
else
    source = strjoin(active,"|");
end
evidence = struct( ...
    "Applied",logical(requested && reservedCount > 0), ...
    "Source",source, ...
    "SourceCount",double(numel(active)), ...
    "OverlapMultiplicity",double(reservedPlan.OwnershipMap. ...
        PairwiseOverlapMultiplicity), ...
    "ReservedRECount",double(reservedCount), ...
    "BaselineG",double(baselineG), ...
    "ReservedG",double(reservedG), ...
    "ReducedG",logical(reservedG < baselineG), ...
    "CSIRSSymbol",NaN, ...
    "CSIRSSubcarrier",NaN);
if logical(requested) && ~(evidence.Applied && evidence.ReducedG)
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:StrictReservationFailed", ...
        "Canonical reserved-RE execution did not materialize and reduce exact G.");
end
if reservationMode == "single" && evidence.SourceCount ~= 1
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:StrictReservationFailed", ...
        "Single-source reservation did not materialize exactly one source.");
elseif reservationMode == "overlapping" ...
        && ~(evidence.SourceCount >= 2 ...
        && evidence.OverlapMultiplicity > 0)
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:StrictReservationFailed", ...
        "Overlapping reservation did not materialize multiple overlapping sources.");
end
end

