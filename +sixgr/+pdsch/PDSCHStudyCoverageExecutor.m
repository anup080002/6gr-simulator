function result = localRunHARQDecodeTrial(bundle,snr,seed,varargin)
ip = inputParser;
ip.FunctionName = "PDSCHStudyCoverageExecutor HARQ decode trial";
ip.addParameter("ChannelModel","AWGN", ...
    @(x) ischar(x) || (isstring(x) && isscalar(x)));
ip.addParameter("NumReceiveAntennas",[], ...
    @(x) isempty(x) || (isnumeric(x) && isscalar(x) ...
        && isfinite(x) && x == fix(x) && x >= 1));
ip.parse(varargin{:});
harqOpt = ip.Results;
channelModel = upper(strtrim(string(harqOpt.ChannelModel)));
isFading = startsWith(channelModel,"TDL-") ...
    || startsWith(channelModel,"CDL-");
if ~isFading && channelModel ~= "AWGN"
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:InvalidHARQChannel", ...
        "HARQ coverage requires AWGN or a concrete TDL/CDL profile.");
end
if isFading && isempty(harqOpt.NumReceiveAntennas)
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:MissingHARQReceiveAntennas", ...
        "Fading HARQ coverage requires an explicit receive-antenna count.");
end
sequence = [0 2 3 1];
manager = sixgr.pdsch.PDSCHHARQManager(struct("MaxProcesses",16));
identity = strings(1,bundle.NumCodewords);
for cw = 1:bundle.NumCodewords
    identity(cw) = string(sixgr.util.sha256Hex(uint8( ...
        bundle.TransportBlocks{cw}(:))));
end
priorDecode = [];
priorPlans = [];
decoded = false;
combinedObserved = false;
for transmission = 1:numel(sequence)
    rv = sequence(transmission);
    trialBundle = bundle;
    trialBundle.Assignment = localCloneAssignment( ...
        bundle.Assignment,"RVPerCodeword", ...
        rv*ones(1,bundle.NumCodewords));
    trialBundle.ReceiverConfig.NewDataPerCodeword = ...
        repmat(transmission == 1,1,bundle.NumCodewords);
    trialBundle.ReceiverConfig.TBIdentityDigestPerCodeword = identity;
    tx = sixgr.pdsch.PDSCHTransmitter( ...
        trialBundle.TransportBlocks,trialBundle.Assignment, ...
        trialBundle.ResourcePlan,trialBundle.Carrier, ...
        trialBundle.ReferenceConfig, ...
        "PrecoderBundle",trialBundle.PrecoderBundle);
    transmissionSeed = seed+7919*transmission;
    if isFading
        [waveform,gridNoise] = localCanonicalFadingWaveform( ...
            tx,channelModel,transmissionSeed,snr,false, ...
            double(harqOpt.NumReceiveAntennas));
        trialBundle.ReceiverConfig.ChannelModel = char(channelModel);
        trialBundle.ReceiverConfig.NPhysicalRxAntennas = size(waveform,2);
        trialBundle.ReceiverConfig.NoiseVariance = gridNoise;
    else
        waveform = localAWGNWaveform( ...
            tx.Waveform,transmissionSeed,snr);
        gridNoise = localGridNoiseVariance(tx,waveform,snr);
    end
    rx = localStrictReceive(waveform,trialBundle,gridNoise, ...
        "CodingPlans",tx.CodingPlans, ...
        "HARQManager",manager);
    currentPlans = rx.CodingPlans;
    if transmission == 1
        combinedDecode = rx.Decode;
    else
        combinedDecode = sixgr.pdsch.DLSCHDecoder( ...
            localUnwrapOne(rx.DescrambledLLR), ...
            "CodingPlan",localUnwrapOne(currentPlans), ...
            "MaxIterations",trialBundle.ReceiverConfig.MaxIterations, ...
            "Algorithm",trialBundle.ReceiverConfig.Algorithm, ...
            "PriorRecoveredLLR",priorDecode, ...
            "PriorCodingPlan",localUnwrapOne(priorPlans), ...
            "HARQKey","coverage_harq_process_0");
        if bundle.NumCodewords == 1
            combinedObserved = logical( ...
                combinedDecode.HARQCombineInfo.Applied);
        else
            combinedObserved = combinedObserved || all(cellfun( ...
                @(x) logical(x.HARQCombineInfo.Applied), ...
                combinedDecode.Codewords));
        end
    end
    decoded = logical(combinedDecode.CRCPass);
    if decoded
        break;
    end
    priorDecode = combinedDecode;
    priorPlans = currentPlans;
end
if ~decoded && numel(sequence) > 1 && ~combinedObserved
    error("sixgr:pdsch:PDSCHStudyCoverageExecutor:HARQCombiningNotApplied", ...
        "HARQ campaign exhausted retransmissions without position-aware combining.");
end
result = struct( ...
    "Decoded",logical(decoded), ...
    "CombiningApplied",logical(combinedObserved), ...
    "RVSequence",localEncodeIntegers(sequence(1:transmission)), ...
    "TransmissionCount",double(transmission));
end

