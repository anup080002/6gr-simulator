raw = double(raw(:).');
if isscalar(raw), raw = repmat(raw,1,count); end
if numel(raw) ~= count || any(~isfinite(raw)) ...
        || any(raw <= 0 | raw ~= fix(raw))
    error("sixgr:pdsch:PDSCHReceiver:CodewordParameterMismatch", ...
        "Nref must be empty or one positive integer per codeword.");
end
cells = num2cell(raw);
end

