function metrics = localStrictMetrics(plan,dmrsIndices,ptrsIndices, ...
        layerSymbols,codewordSymbols,scrambledLLR,descrambledLLR, ...
        decode,contract,noiseVariance,crcPass,receiverConfig, ...
        channelGain,pilotReconstructionNMSE)
safeNoise = max(double(noiseVariance),eps);
sinrPerLayer = zeros(1,contract.NumLayers);
for layer = 1:contract.NumLayers
    sinrPerLayer(layer) = 10*log10( ...
        mean(abs(layerSymbols(:,layer)).^2)/safeNoise);
end
evmPerCodeword = zeros(1,contract.NumCodewords);
rateRecoveredCount = zeros(1,contract.NumCodewords);
iterations = zeros(1,contract.NumCodewords);
for cw = 1:contract.NumCodewords
    hardBits = sixgr.pdsch.PDSCHModulator(codewordSymbols{cw}, ...
        contract.Modulation(cw),"Operation","hard-demap");
    remodulated = sixgr.pdsch.PDSCHModulator( ...
        hardBits,contract.Modulation(cw));
    denominator = max(mean(abs(remodulated).^2),eps);
    evmPerCodeword(cw) = sqrt(mean(abs( ...
        codewordSymbols{cw}(:)-remodulated(:)).^2)/denominator);
    if contract.NumCodewords == 1
        decoded = decode;
    else
        decoded = decode.Codewords{cw};
    end
    rateRecoveredCount(cw) = numel(decoded.RateRecoveredLLR);
    iterations(cw) = mean(double(decoded.ActiveIterations(:)),"omitnan");
end
channelNMSE = double(pilotReconstructionNMSE);
channelNMSESource = ...
    "dmrs_pilot_reconstruction_residual_not_true_channel_oracle";
if isfield(receiverConfig,"ReferenceChannelGain") ...
        && ~isempty(receiverConfig.ReferenceChannelGain)
    truthGain = complex(double(receiverConfig.ReferenceChannelGain(:)));
    if numel(truthGain) ~= numel(channelGain)
        error("sixgr:pdsch:PDSCHReceiver:ReferenceChannelShapeMismatch", ...
            "ReferenceChannelGain must contain one value per physical port.");
    end
    channelNMSE = sum(abs(channelGain-truthGain).^2) ...
        / max(sum(abs(truthGain).^2),eps);
    channelNMSESource = ...
        "explicit_awgn_reference_gain_test_contract";
end
metrics = struct( ...
    "DataRECount",double(plan.ExactDataRECount), ...
    "DMRSRECount",double(numel(dmrsIndices)), ...
    "PTRSRECount",double(numel(ptrsIndices)), ...
    "ChannelEstimateNMSE",double(channelNMSE), ...
    "ChannelEstimateNMSESource",channelNMSESource, ...
    "MeasuredPostEqualizationSINRdBPerLayer",sinrPerLayer, ...
    "EVMPerCodeword",evmPerCodeword, ...
    "ScrambledLLRCountPerCodeword",cellfun(@numel,scrambledLLR), ...
    "DescrambledLLRCountPerCodeword",cellfun(@numel,descrambledLLR), ...
    "FiniteDescrambledLLRCountPerCodeword", ...
        cellfun(@(x) nnz(isfinite(x)),descrambledLLR), ...
    "RateRecoveredBitCountPerCodeword",rateRecoveredCount, ...
    "LDPCIterationCountPerCodeword",iterations, ...
    "BERPerCodeword",NaN(1,contract.NumCodewords), ...
    "BLERPerCodeword",double(~crcPass), ...
    "TBCRCPassPerCodeword",logical(crcPass), ...
    "BERStatus","unavailable_without_external_decoded_bit_reference");
end

function values = localRXNumeric(raw,count,name)
values = double(raw(:).');
if numel(values) ~= count || any(~isfinite(values))
    error("sixgr:pdsch:PDSCHReceiver:CodewordParameterMismatch", ...
        "%s must contain one finite value per codeword.",name);
end
end

function values = localRXStrings(raw,count,name)
values = reshape(string(raw),1,[]);
if numel(values) ~= count || any(strlength(strtrim(values)) == 0)
    error("sixgr:pdsch:PDSCHReceiver:CodewordParameterMismatch", ...
        "%s must contain one nonempty value per codeword.",name);
end
end

function qm = localRXQm(modulation)
switch upper(erase(string(modulation)," "))
    case "QPSK", qm = 2;
    case "16QAM", qm = 4;
    case "64QAM", qm = 6;
    case "256QAM", qm = 8;
    case "1024QAM", qm = 10;
    otherwise
        error("sixgr:pdsch:PDSCHReceiver:UnsupportedModulation", ...
            "Unsupported PDSCH modulation '%s'.",modulation);
end
end

function cells = localRXOptional(raw,count)
