classdef PDSCHArtifactExporter
    %PDSCHARTIFACTEXPORTER Fail-closed PDSCH CSV and figure publisher.
    %
    % Input tables must already be derived from production execution.  This
    % class validates and publishes them; it never manufactures missing
    % primary rows or copies expected-vector output into the result set.

    methods (Static)
        function summary = export(tables, outputDir, vectorRoot)
            if ~isstruct(tables) || ~isscalar(tables)
                error("sixgr:pdsch:ArtifactTablesInvalid", ...
                    "PDSCH artifact input must be a scalar struct of MATLAB tables.");
            end
            outputDir = char(string(outputDir));
            vectorRoot = char(string(vectorRoot));
            if ~isfolder(vectorRoot)
                error("sixgr:pdsch:ArtifactVectorRootMissing", ...
                    "PDSCH vector root does not exist: %s", vectorRoot);
            end
            csvContractPath = fullfile( ...
                vectorRoot, "desired_pdsch_csv_contract.csv");
            imageContractPath = fullfile( ...
                vectorRoot, "desired_pdsch_image_contract.csv");
            if ~isfile(csvContractPath) || ~isfile(imageContractPath)
                error("sixgr:pdsch:ArtifactContractMissing", ...
                    "Both desired PDSCH CSV and image contracts are required.");
            end
            csvContract = sixgr.pdsch.PDSCHArtifactExporter. ...
                readStringTable(csvContractPath);
            imageContract = sixgr.pdsch.PDSCHArtifactExporter. ...
                readStringTable(imageContractPath);
            additionalImageContract = sixgr.pdsch.PDSCHArtifactExporter. ...
                additionalImageContract();
            requiredCSV = csvContract( ...
                sixgr.pdsch.PDSCHArtifactExporter.truthColumn( ...
                csvContract.Required), :);
            semanticName = "pdsch_image_semantic_audit.csv";
            primaryContract = requiredCSV( ...
                requiredCSV.FileName ~= semanticName, :);
            if height(primaryContract) ~= 14 || height(imageContract) ~= 9
                error("sixgr:pdsch:ArtifactContractUnexpected", ...
                    "Expected 14 primary CSVs and 9 contracted PNGs.");
            end

            if ~isfolder(outputDir)
                [created, message] = mkdir(outputDir);
                if ~created
                    error("sixgr:pdsch:ArtifactOutputCreateFailed", ...
                        "Unable to create artifact output directory: %s", message);
                end
            end
            extraImages = additionalImageContract.ImageFile;
            allImageContract = [imageContract; additionalImageContract];
            allTargets = [ ...
                string(requiredCSV.FileName(:)); ...
                string(allImageContract.ImageFile(:))];
            for i = 1:numel(allTargets)
                target = fullfile(outputDir, allTargets(i));
                if isfile(target) || isfolder(target)
                    error("sixgr:pdsch:ArtifactTargetAlreadyExists", ...
                        "Refusing to mix new evidence with existing target: %s", ...
                        target);
                end
            end

            stageDir = tempname(outputDir);
            [created, message] = mkdir(stageDir);
            if ~created
                error("sixgr:pdsch:ArtifactStageCreateFailed", ...
                    "Unable to create artifact staging directory: %s", message);
            end
            cleanup = onCleanup(@() ...
                sixgr.pdsch.PDSCHArtifactExporter.removeStage(stageDir));

            stagedTables = struct();
            csvNames = strings(height(primaryContract), 1);
            csvRows = zeros(height(primaryContract), 1);
            for i = 1:height(primaryContract)
                fileName = primaryContract.FileName(i);
                fieldName = erase(fileName, ".csv");
                if ~isfield(tables, fieldName) || ...
                        ~istable(tables.(fieldName))
                    error("sixgr:pdsch:ArtifactTableMissing", ...
                        "Missing production-derived table '%s' for %s.", ...
                        fieldName, fileName);
                end
                value = tables.(fieldName);
                expectedColumns = split( ...
                    primaryContract.RequiredColumns(i), "|");
                expectedColumns = expectedColumns(:).';
                primaryKey = split(primaryContract.PrimaryKey(i), "|");
                primaryKey = primaryKey(:).';
                sixgr.pdsch.PDSCHArtifactExporter.validatePrimaryTable( ...
                    value, fileName, expectedColumns, primaryKey);
                path = fullfile(stageDir, fileName);
                writetable(value, path, "Encoding", "UTF-8");
                stagedTables.(fieldName) = ...
                    sixgr.pdsch.PDSCHArtifactExporter. ...
                    readStringTable(path);
                csvNames(i) = fileName;
                csvRows(i) = height(value);
            end

            semanticRows = cell(height(allImageContract), 1);
            imageNames = strings(height(imageContract), 1);
            for i = 1:height(allImageContract)
                contractRow = allImageContract(i, :);
                imageName = contractRow.ImageFile(1);
                [figureHandle, axesHandle] = ...
                    sixgr.pdsch.PDSCHArtifactExporter. ...
                    createContractFigure( ...
                    imageName, stagedTables, contractRow);
                imagePath = fullfile(stageDir, imageName);
                semanticRows{i} = ...
                    sixgr.pdsch.PDSCHArtifactExporter. ...
                    saveAndInspectFigure( ...
                    figureHandle, axesHandle, imagePath, ...
                    contractRow, stageDir);
                if i <= height(imageContract)
                    imageNames(i) = imageName;
                end
            end

            semanticAudit = vertcat(semanticRows{:});
            semanticContract = requiredCSV( ...
                requiredCSV.FileName == semanticName, :);
            expectedSemanticColumns = split( ...
                semanticContract.RequiredColumns(1), "|");
            expectedSemanticColumns = expectedSemanticColumns(:).';
            semanticKey = split(semanticContract.PrimaryKey(1), "|");
            semanticKey = semanticKey(:).';
            sixgr.pdsch.PDSCHArtifactExporter.validatePrimaryTable( ...
                semanticAudit, semanticName, ...
                expectedSemanticColumns, semanticKey);
            writetable(semanticAudit, ...
                fullfile(stageDir, semanticName), "Encoding", "UTF-8");

            publishNames = [csvNames; semanticName; imageNames; extraImages(:)];
            for i = 1:numel(publishNames)
                source = fullfile(stageDir, publishNames(i));
                destination = fullfile(outputDir, publishNames(i));
                [moved, message] = movefile(source, destination);
                if ~moved
                    error("sixgr:pdsch:ArtifactPublishFailed", ...
                        "Unable to publish %s: %s", publishNames(i), message);
                end
            end

            summary = struct( ...
                "Passed", true, ...
                "OutputDir", string(outputDir), ...
                "CSVFiles", [csvNames; semanticName], ...
                "CSVRowCounts", [csvRows; height(semanticAudit)], ...
                "ContractedPNGFiles", imageNames, ...
                "AdditionalPNGFiles", extraImages(:), ...
                "SemanticAudit", semanticAudit, ...
                "PrimaryTableCount", height(primaryContract), ...
                "ContractedImageCount", height(imageContract), ...
                "AuditedImageCount", height(allImageContract));
            clear cleanup
        end
    end

    methods (Static, Access = private)
        function value = readStringTable(path)
            options = detectImportOptions(path, ...
                "Delimiter", ",", "VariableNamingRule", "preserve");
            options = setvartype( ...
                options, options.VariableNames, "string");
            value = readtable(path, options);
            for i = 1:width(value)
                name = value.Properties.VariableNames{i};
                column = string(value.(name));
                column(ismissing(column)) = "";
                value.(name) = column;
            end
        end

        function value = truthColumn(column)
            token = upper(strtrim(string(column)));
            value = ismember(token, ["1","TRUE","YES","PASS"]);
        end

        function value = additionalImageContract()
            value = table( ...
                [ ...
                    "pdsch_pipeline_stage_dimensions.png"; ...
                    "pdsch_independent_mismatch_overview.png"], ...
                [ ...
                    "pdsch_coding_chain.csv"; ...
                    "pdsch_independent_vector_results.csv"], ...
                ["Pipeline stage"; "Independent comparison"], ...
                ["Bits"; "Mismatch / error"], ...
                [ ...
                    "PDSCH pipeline stage dimensions"; ...
                    "Independent-vector mismatch overview"], ...
                ["1"; "1"], ["1"; "2"], ["5"; "8"], ...
                ["900"; "900"], ["600"; "600"], ...
                'VariableNames', { ...
                    'ImageFile','SourceCSV','ExpectedXLabel', ...
                    'ExpectedYLabel','ExpectedTitleToken', ...
                    'MinAxesCount','MinSeriesCount', ...
                    'MinFinitePointCount','MinWidth','MinHeight'});
        end

        function validatePrimaryTable(value, fileName, ...
                expectedColumns, primaryKey)
            actualColumns = string(value.Properties.VariableNames);
            acceptedColumns = expectedColumns;
            if string(fileName) == "pdsch_image_semantic_audit.csv"
                acceptedColumns = [acceptedColumns, ...
                    "ActualPlotSourceCSV", ...
                    "ActualPlotSourceCSV_SHA256"];
            elseif any(string(fileName) == [ ...
                    "pdsch_dmrs_matrix.csv", ...
                    "pdsch_ptrs_matrix.csv"])
                acceptedColumns = [acceptedColumns, ...
                    "PlotCoordinates0Based"];
            end
            if ~isequal(actualColumns, acceptedColumns)
                error("sixgr:pdsch:ArtifactSchemaMismatch", ...
                    "%s schema differs from the exact contract. Expected " + ...
                    "%s; received %s.", fileName, ...
                    strjoin(acceptedColumns, "|"), ...
                    strjoin(actualColumns, "|"));
            end
            if height(value) < 1
                error("sixgr:pdsch:ArtifactEmptyTable", ...
                    "%s has no production-derived rows.", fileName);
            end
            status = upper(strtrim( ...
                sixgr.pdsch.PDSCHArtifactExporter. ...
                textColumn(value, "Status")));
            if any(status ~= "PASS")
                error("sixgr:pdsch:ArtifactNonPassRow", ...
                    "%s contains a row whose Status is not PASS.", fileName);
            end

            keys = strings(height(value), numel(primaryKey));
            for i = 1:numel(primaryKey)
                name = primaryKey(i);
                if ~ismember(name, actualColumns)
                    error("sixgr:pdsch:ArtifactPrimaryKeyMissing", ...
                        "%s primary-key column %s is absent.", fileName, name);
                end
                keys(:, i) = sixgr.pdsch.PDSCHArtifactExporter. ...
                    textColumn(value, name);
                if any(ismissing(keys(:, i)) | ...
                        strlength(strtrim(keys(:, i))) == 0)
                    error("sixgr:pdsch:ArtifactPrimaryKeyEmpty", ...
                        "%s contains an empty primary-key value in %s.", ...
                        fileName, name);
                end
            end
            combined = join(keys, char(31), 2);
            if numel(unique(combined)) ~= numel(combined)
                error("sixgr:pdsch:ArtifactDuplicatePrimaryKey", ...
                    "%s contains duplicate primary-key rows.", fileName);
            end

            if ismember("Source", actualColumns)
                source = lower(sixgr.pdsch.PDSCHArtifactExporter. ...
                    textColumn(value, "Source"));
                prohibited = contains(source, "fallback") | ...
                    contains(source, "synthetic") | ...
                    contains(source, "proxy");
                if any(prohibited)
                    error("sixgr:pdsch:ArtifactDishonestSource", ...
                        "%s contains fallback, synthetic, or proxy primary rows.", ...
                        fileName);
                end
            end
        end

        function [fig, ax] = createContractFigure( ...
                imageName, tables, contract)
            fig = figure( ...
                "Visible", "off", "Color", "white", ...
                "Units", "inches", "Position", [1 1 12 8], ...
                "Renderer", "painters");
            ax = axes(fig);
            hold(ax, "on");
            grid(ax, "on");
            box(ax, "on");
            ax.FontName = "Arial";
            ax.FontSize = 11;
            ax.LineWidth = 1;

            switch imageName
                case "pdsch_resource_grid_ownership.png"
                    value = tables.pdsch_resource_ownership;
                    x = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "PRB") + ...
                        sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "Subcarrier") / 12;
                    y = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "Symbol");
                    owner = sixgr.pdsch.PDSCHArtifactExporter. ...
                        textColumn(value, "Owner");
                    [~, ~, color] = unique(owner, "stable");
                    scatter(ax, x, y, 28, color, "filled", ...
                        "MarkerFaceAlpha", 0.8, ...
                        "DisplayName", "Resolved ownership");
                    ax.YDir = "reverse";

                case "pdsch_dmrs_ptrs_map.png"
                    [dx, dy, px, py] = ...
                        sixgr.pdsch.PDSCHArtifactExporter. ...
                        exactReferenceCoordinates( ...
                        tables.pdsch_dmrs_matrix, ...
                        tables.pdsch_ptrs_matrix);
                    scatter(ax, dx, dy, 28, "filled", ...
                        "MarkerFaceAlpha", 0.35, ...
                        "DisplayName", ...
                        "Persisted production DM-RS RE");
                    scatter(ax, px, py, 42, "diamond", "filled", ...
                        "MarkerFaceAlpha", 0.55, ...
                        "DisplayName", ...
                        "Persisted production PT-RS RE");
                    legend(ax, "Location", "best");
                    ax.YDir = "reverse";

                case "pdsch_codeword_layer_mapping.png"
                    value = tables.pdsch_layer_codeword_map;
                    x = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "Layer");
                    y = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "MappedSymbolCount");
                    codeword = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "Codeword");
                    for cw = unique(codeword(:)).'
                        mask = codeword == cw;
                        plot(ax, x(mask), y(mask), "-o", ...
                            "LineWidth", 1.7, ...
                            "DisplayName", "Codeword " + string(cw));
                    end
                    legend(ax, "Location", "best");

                case "pdsch_prg_precoding_map.png"
                    value = tables.pdsch_precoding_application;
                    prg = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "PRG");
                    prbStart = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "PRBStart");
                    prbEnd = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "PRBEnd");
                    powerError = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "PowerRelativeError");
                    prbCenter = 0.5 * (prbStart + prbEnd);
                    normalizedPower = 1 - powerError;
                    if any(~isfinite(prbCenter) | ~isfinite(prg) | ...
                            ~isfinite(normalizedPower) | ...
                            normalizedPower < 0)
                        close(fig);
                        error("sixgr:pdsch:ArtifactPrecoderEvidenceInvalid", ...
                            "PRG, PRB span, and normalized precoder power " + ...
                            "must be finite production evidence.");
                    end
                    scatter(ax, prbCenter, prg, 48, "o", "filled", ...
                        "DisplayName", "Applied PRG index");
                    scatter(ax, prbCenter, normalizedPower, 52, "s", ...
                        "LineWidth", 1.3, ...
                        "DisplayName", ...
                        "Normalized power (1 - relative error)");
                    legend(ax, "Location", "best");

                case "pdsch_harq_rv_timeline.png"
                    value = tables.pdsch_harq_trials;
                    x = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "TransmissionIndex");
                    rv = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "RV");
                    decoded = double(sixgr.pdsch.PDSCHArtifactExporter. ...
                        truthText(sixgr.pdsch.PDSCHArtifactExporter. ...
                        textColumn(value, "TBCRCOK")));
                    plot(ax, x, rv, "-o", "LineWidth", 1.7, ...
                        "DisplayName", "RV");
                    plot(ax, x, decoded, "--s", "LineWidth", 1.7, ...
                        "DisplayName", "TB CRC pass");
                    legend(ax, "Location", "best");

                case "pdsch_bler_vs_snr.png"
                    value = tables.pdsch_bler_curve;
                    x = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "SNRdB");
                    y = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "BLER");
                    campaign = sixgr.pdsch.PDSCHArtifactExporter. ...
                        textColumn(value, "CampaignID");
                    for name = unique(campaign(:), "stable").'
                        mask = campaign == name;
                        [sortedX, order] = sort(x(mask));
                        selectedY = y(mask);
                        semilogy(ax, sortedX, max(selectedY(order), eps), ...
                            "-o", "LineWidth", 1.8, ...
                            "DisplayName", name);
                    end
                    legend(ax, "Location", "best");

                case "pdsch_ptrs_phase_noise_evm.png"
                    value = tables.pdsch_ptrs_matrix;
                    x = abs(sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "CPEBeforeDeg"));
                    before = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "EVMBeforePercent");
                    after = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "EVMAfterPercent");
                    [x, order] = sort(x);
                    plot(ax, x, before(order), "-o", "LineWidth", 1.7, ...
                        "DisplayName", "Before PT-RS correction");
                    plot(ax, x, after(order), "--s", "LineWidth", 1.7, ...
                        "DisplayName", "After PT-RS correction");
                    legend(ax, "Location", "best");

                case "pdsch_per_layer_sinr.png"
                    value = tables.pdsch_receiver_metrics;
                    x = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "Layer");
                    y = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "MeasuredSINRdB");
                    scatter(ax, x, y, 42, "filled", ...
                        "DisplayName", "Measured layer SINR");

                case "pdsch_reserved_re_impact.png"
                    [reserved, g, tbs] = ...
                        sixgr.pdsch.PDSCHArtifactExporter. ...
                        alignedReservedImpact( ...
                        tables.pdsch_resource_ownership, ...
                        tables.pdsch_coding_chain);
                    plot(ax, reserved, g, "-o", "LineWidth", 1.7, ...
                        "DisplayName", "G");
                    plot(ax, reserved, tbs, "--s", "LineWidth", 1.7, ...
                        "DisplayName", "TBS");
                    legend(ax, "Location", "best");

                case "pdsch_pipeline_stage_dimensions.png"
                    value = tables.pdsch_coding_chain;
                    stages = [ ...
                        mean(sixgr.pdsch.PDSCHArtifactExporter. ...
                            numericColumn(value, "TBS"), "omitnan"), ...
                        mean(sixgr.pdsch.PDSCHArtifactExporter. ...
                            numericColumn(value, "K"), "omitnan"), ...
                        mean(sixgr.pdsch.PDSCHArtifactExporter. ...
                            numericColumn(value, "N"), "omitnan"), ...
                        mean(sixgr.pdsch.PDSCHArtifactExporter. ...
                            numericColumn(value, "G"), "omitnan"), ...
                        mean(sixgr.pdsch.PDSCHArtifactExporter. ...
                            numericColumn(value, "RateMatchedBits"), ...
                            "omitnan")];
                    bar(ax, 1:5, stages, ...
                        "DisplayName", "Mean executed bit count");
                    xticks(ax, 1:5);
                    xticklabels(ax, ...
                        ["TBS","K","N","G","Rate matched"]);

                case "pdsch_independent_mismatch_overview.png"
                    value = tables.pdsch_independent_vector_results;
                    x = (1:height(value)).';
                    mismatch = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "MismatchCount");
                    maxError = sixgr.pdsch.PDSCHArtifactExporter. ...
                        numericColumn(value, "MaxAbsError");
                    plot(ax, x, mismatch, "-o", "LineWidth", 1.5, ...
                        "DisplayName", "Mismatch count");
                    plot(ax, x, maxError, "--s", "LineWidth", 1.5, ...
                        "DisplayName", "Maximum absolute error");
                    legend(ax, "Location", "best");

                otherwise
                    close(fig);
                    error("sixgr:pdsch:ArtifactUnknownImageContract", ...
                        "No MATLAB plot implementation exists for %s.", imageName);
            end
            xlabel(ax, contract.ExpectedXLabel(1));
            ylabel(ax, contract.ExpectedYLabel(1));
            title(ax, contract.ExpectedTitleToken(1), ...
                "FontWeight", "bold");
            hold(ax, "off");
        end

        function row = saveAndInspectFigure(fig, ax, imagePath, ...
                contract, stageDir)
            cleanup = onCleanup(@() close(fig));
            drawnow;
            axesCount = numel(findall(fig, "Type", "axes"));
            [seriesCount, finitePoints] = ...
                sixgr.pdsch.PDSCHArtifactExporter.seriesSemantics(ax);
            actualX = string(ax.XLabel.String);
            actualY = string(ax.YLabel.String);
            actualTitle = string(ax.Title.String);
            exportgraphics(fig, imagePath, ...
                "Resolution", 100, "BackgroundColor", "white");
            metadata = imfinfo(imagePath);
            width = double(metadata.Width);
            height = double(metadata.Height);

            minimumAxes = str2double(contract.MinAxesCount(1));
            minimumSeries = str2double(contract.MinSeriesCount(1));
            minimumPoints = str2double(contract.MinFinitePointCount(1));
            minimumWidth = str2double(contract.MinWidth(1));
            minimumHeight = str2double(contract.MinHeight(1));
            if axesCount < minimumAxes || seriesCount < minimumSeries || ...
                    finitePoints < minimumPoints
                error("sixgr:pdsch:ArtifactFigureSemanticFailure", ...
                    "%s has axes/series/points %d/%d/%d below %d/%d/%d.", ...
                    contract.ImageFile(1), axesCount, seriesCount, ...
                    finitePoints, minimumAxes, minimumSeries, minimumPoints);
            end
            if width < minimumWidth || height < minimumHeight
                error("sixgr:pdsch:ArtifactFigureDimensionFailure", ...
                    "%s is %dx%d; minimum is %dx%d.", ...
                    contract.ImageFile(1), width, height, ...
                    minimumWidth, minimumHeight);
            end
            if strtrim(actualX) ~= strtrim(contract.ExpectedXLabel(1)) || ...
                    strtrim(actualY) ~= strtrim(contract.ExpectedYLabel(1)) || ...
                    ~contains(lower(actualTitle), ...
                    lower(contract.ExpectedTitleToken(1)))
                error("sixgr:pdsch:ArtifactFigureLabelFailure", ...
                    "%s labels or title do not match the image contract.", ...
                    contract.ImageFile(1));
            end

            sources = split(contract.SourceCSV(1), "|");
            sources = sources(:).';
            sourceHash = strings(1, numel(sources));
            for i = 1:numel(sources)
                hash = sixgr.pdsch.PDSCHArtifactExporter.sha256( ...
                    fullfile(stageDir, sources(i)));
                if numel(sources) == 1
                    sourceHash(i) = hash;
                else
                    sourceHash(i) = sources(i) + "=" + hash;
                end
            end
            sourceHashText = strjoin(sourceHash, "|");
            actualSources = sources;
            actualSourceHash = strings(1, numel(actualSources));
            for i = 1:numel(actualSources)
                hash = sixgr.pdsch.PDSCHArtifactExporter.sha256( ...
                    fullfile(stageDir, actualSources(i)));
                if numel(actualSources) == 1
                    actualSourceHash(i) = hash;
                else
                    actualSourceHash(i) = actualSources(i) + "=" + hash;
                end
            end
            actualSourceHashText = strjoin(actualSourceHash, "|");
            pngHash = sixgr.pdsch.PDSCHArtifactExporter.sha256(imagePath);
            row = table( ...
                string(contract.ImageFile(1)), ...
                string(contract.SourceCSV(1)), ...
                width, height, double(axesCount), ...
                double(seriesCount), double(finitePoints), ...
                string(contract.ExpectedXLabel(1)), actualX, ...
                string(contract.ExpectedYLabel(1)), actualY, ...
                string(contract.ExpectedTitleToken(1)), actualTitle, ...
                sourceHashText, pngHash, "PASS", ...
                strjoin(actualSources, "|"), actualSourceHashText, ...
                'VariableNames', { ...
                'ImageFile','SourceCSV','Width','Height','AxesCount', ...
                'SeriesCount','FinitePointCount','ExpectedXLabel', ...
                'ActualXLabel','ExpectedYLabel','ActualYLabel', ...
                'ExpectedTitleToken','ActualTitle', ...
                'SourceCSV_SHA256','PNG_SHA256','Status', ...
                'ActualPlotSourceCSV','ActualPlotSourceCSV_SHA256'});
            clear cleanup
        end

        function [seriesCount, finitePoints] = seriesSemantics(ax)
            children = allchild(ax);
            seriesCount = 0;
            finitePoints = 0;
            for i = 1:numel(children)
                item = children(i);
                if isprop(item, "XData") && isprop(item, "YData")
                    x = double(item.XData(:));
                    y = double(item.YData(:));
                    n = min(numel(x), numel(y));
                    if n > 0
                        seriesCount = seriesCount + 1;
                        finitePoints = finitePoints + ...
                            nnz(isfinite(x(1:n)) & isfinite(y(1:n)));
                    end
                end
            end
        end

        function [dmrsX, dmrsY, ptrsX, ptrsY] = ...
                exactReferenceCoordinates(dmrs, ptrs)
            dmrsCoordinates = ...
                sixgr.pdsch.PDSCHArtifactExporter. ...
                decodeReferenceCoordinates(dmrs, "DMRSRECount", "DM-RS");
            ptrsCoordinates = ...
                sixgr.pdsch.PDSCHArtifactExporter. ...
                decodeReferenceCoordinates(ptrs, "PTRSRECount", "PT-RS");
            if isempty(dmrsCoordinates) || isempty(ptrsCoordinates)
                error("sixgr:pdsch:ArtifactReferenceREMissing", ...
                    "Persisted DM-RS and PT-RS matrix CSVs must contain " + ...
                    "nonempty production plot coordinates.");
            end
            dmrsX = dmrsCoordinates(:, 1);
            dmrsY = dmrsCoordinates(:, 2);
            ptrsX = ptrsCoordinates(:, 1);
            ptrsY = ptrsCoordinates(:, 2);
        end

        function coordinates = decodeReferenceCoordinates( ...
                value, countColumn, label)
            if ~ismember("PlotCoordinates0Based", ...
                    string(value.Properties.VariableNames))
                error("sixgr:pdsch:ArtifactReferenceCoordinatesMissing", ...
                    "%s matrix lacks PlotCoordinates0Based.", label);
            end
            encoded = sixgr.pdsch.PDSCHArtifactExporter. ...
                textColumn(value, "PlotCoordinates0Based");
            expectedCounts = sixgr.pdsch.PDSCHArtifactExporter. ...
                numericColumn(value, countColumn);
            coordinates = zeros(0, 2);
            for row = 1:height(value)
                token = strtrim(encoded(row));
                if strlength(token) == 0
                    rowCoordinates = zeros(0, 2);
                else
                    pairs = split(token, "|");
                    rowCoordinates = zeros(numel(pairs), 2);
                    for pair = 1:numel(pairs)
                        components = split(pairs(pair), ":");
                        if numel(components) ~= 2
                            error("sixgr:pdsch:ArtifactReferenceREInvalid", ...
                                "%s row %d has a malformed coordinate.", ...
                                label, row);
                        end
                        rowCoordinates(pair, :) = ...
                            str2double(components(:)).';
                    end
                end
                if any(~isfinite(rowCoordinates), "all") ...
                        || any(rowCoordinates < 0, "all") ...
                        || any(rowCoordinates ~= floor(rowCoordinates), "all")
                    error("sixgr:pdsch:ArtifactReferenceREInvalid", ...
                        "%s coordinates must be finite nonnegative " + ...
                        "zero-based integer pairs.", label);
                end
                if ~(isfinite(expectedCounts(row)) ...
                        && expectedCounts(row) >= 0 ...
                        && expectedCounts(row) == fix(expectedCounts(row)) ...
                        && size(rowCoordinates, 1) == expectedCounts(row))
                    error("sixgr:pdsch:ArtifactReferenceRECountMismatch", ...
                        "%s row %d declares %.17g REs but contains %d " + ...
                        "plot coordinates.", label, row, ...
                        expectedCounts(row), size(rowCoordinates, 1));
                end
                coordinates = [coordinates; rowCoordinates]; %#ok<AGROW>
            end
        end

        function [reserved, g, tbs] = alignedReservedImpact( ...
                ownership, coding)
            ownershipCases = sixgr.pdsch.PDSCHArtifactExporter. ...
                textColumn(ownership, "CaseID");
            codingCases = sixgr.pdsch.PDSCHArtifactExporter. ...
                textColumn(coding, "CaseID");
            common = intersect(unique(ownershipCases, "stable"), ...
                unique(codingCases, "stable"), "stable");
            if numel(common) < 2
                error("sixgr:pdsch:ArtifactReservedEvidenceUnaligned", ...
                    "Reserved-resource impact requires at least two real " + ...
                    "ownership/coding executions with the same CaseID.");
            end

            owner = lower(sixgr.pdsch.PDSCHArtifactExporter. ...
                textColumn(ownership, "Owner"));
            slot = sixgr.pdsch.PDSCHArtifactExporter. ...
                numericColumn(ownership, "Slot");
            prb = sixgr.pdsch.PDSCHArtifactExporter. ...
                numericColumn(ownership, "PRB");
            symbol = sixgr.pdsch.PDSCHArtifactExporter. ...
                numericColumn(ownership, "Symbol");
            subcarrier = sixgr.pdsch.PDSCHArtifactExporter. ...
                numericColumn(ownership, "Subcarrier");
            codingG = sixgr.pdsch.PDSCHArtifactExporter. ...
                numericColumn(coding, "G");
            codingTBS = sixgr.pdsch.PDSCHArtifactExporter. ...
                numericColumn(coding, "TBS");

            reservedAll = zeros(numel(common), 1);
            gAll = zeros(numel(common), 1);
            tbsAll = zeros(numel(common), 1);
            geometry = strings(numel(common), 1);
            for i = 1:numel(common)
                ownMask = ownershipCases == common(i);
                codeMask = codingCases == common(i);
                coordinates = [ ...
                    slot(ownMask), prb(ownMask), ...
                    symbol(ownMask), subcarrier(ownMask)];
                coordinates = sortrows(coordinates, [1 2 3 4]);
                geometry(i) = strjoin(compose( ...
                    "%.0f:%.0f:%.0f:%.0f", ...
                    coordinates(:, 1), coordinates(:, 2), ...
                    coordinates(:, 3), coordinates(:, 4)), "|");
                reservedAll(i) = nnz(ownMask & ...
                    startsWith(owner, "reserved"));
                gAll(i) = sum(codingG(codeMask));
                tbsAll(i) = sum(codingTBS(codeMask));
            end
            if any(~isfinite(gAll) | gAll <= 0 | ...
                    ~isfinite(tbsAll) | tbsAll <= 0)
                error("sixgr:pdsch:ArtifactReservedEvidenceInvalid", ...
                    "Aligned reserved-resource coding rows require positive finite G and TBS.");
            end

            geometryKeys = unique(geometry, "stable");
            selected = false(numel(common), 1);
            bestCount = 0;
            for i = 1:numel(geometryKeys)
                candidate = geometry == geometryKeys(i);
                if any(reservedAll(candidate) == 0) && ...
                        any(reservedAll(candidate) > 0) && ...
                        nnz(candidate) > bestCount
                    selected = candidate;
                    bestCount = nnz(candidate);
                end
            end
            if bestCount < 2
                error("sixgr:pdsch:ArtifactReservedEvidenceUnaligned", ...
                    "No exact allocation geometry has both an unreserved " + ...
                    "and a reserved production coding execution.");
            end

            reserved = reservedAll(selected);
            g = gAll(selected);
            tbs = tbsAll(selected);
            baselineG = max(g(reserved == 0));
            if any(g(reserved > 0) >= baselineG)
                error("sixgr:pdsch:ArtifactReservedEvidenceNoImpact", ...
                    "Aligned reserved executions must carry a smaller exact " + ...
                    "rate-matched G than their unreserved execution.");
            end
            [reserved, order] = sort(reserved);
            g = g(order);
            tbs = tbs(order);
            if any(diff(g) > 0)
                error("sixgr:pdsch:ArtifactReservedEvidenceNonmonotonic", ...
                    "Exact G increased as the aligned reserved-RE count increased.");
            end
        end

        function values = numericColumn(value, name)
            raw = value.(char(name));
            if isnumeric(raw) || islogical(raw)
                values = double(raw);
            else
                values = str2double(string(raw));
            end
            values = double(values(:));
        end

        function values = textColumn(value, name)
            raw = value.(char(name));
            values = string(raw);
            values(ismissing(values)) = "";
            values = values(:);
        end

        function values = truthText(text)
            token = upper(strtrim(string(text)));
            values = ismember(token, ...
                ["1","TRUE","YES","Y","PASS"]);
        end

        function values = parseIntegerList(text)
            text = strtrim(string(text));
            if ismissing(text) || strlength(text) == 0
                values = zeros(1, 0);
                return;
            end
            tokens = split(text, "|");
            values = zeros(1, 0);
            for i = 1:numel(tokens)
                token = strtrim(tokens(i));
                range = regexp(char(token), ...
                    '^(-?\d+)-(-?\d+)$', 'tokens', 'once');
                if ~isempty(range)
                    first = str2double(range{1});
                    last = str2double(range{2});
                    values = [values first:last]; %#ok<AGROW>
                else
                    values(end + 1) = str2double(token); %#ok<AGROW>
                end
            end
            if any(~isfinite(values))
                error("sixgr:pdsch:ArtifactNonNumericPlotData", ...
                    "Encoded integer list contains a nonnumeric token.");
            end
            values = double(values(:).');
        end

        function hash = sha256(path)
            fid = fopen(path, "rb");
            if fid < 0
                error("sixgr:pdsch:ArtifactHashReadFailed", ...
                    "Unable to read artifact for SHA-256: %s", path);
            end
            cleanup = onCleanup(@() fclose(fid));
            bytes = fread(fid, inf, "*uint8");
            digest = java.security.MessageDigest.getInstance("SHA-256");
            digest.update(typecast(uint8(bytes), "int8"));
            raw = typecast(digest.digest(), "uint8");
            hash = lower(string(reshape(dec2hex(raw, 2).', 1, [])));
            clear cleanup
        end

        function removeStage(path)
            if isfolder(path)
                rmdir(path, "s");
            end
        end
