classdef PDSCHMultiTRPExecutor
    %PDSCHMULTITRPEXECUTOR Execute bounded noncoherent repetition.
    %
    % Each occasion runs the canonical PDSCHTransmitter and
    % PDSCHReceiver.  Combination consumes the actual descrambled,
    % rate-matched receiver LLR vectors; synthetic observations are not
    % accepted by this execution entry point.

    methods (Static)
        function result = execute(transportBlocks, assignment, ...
                resourcePlan, carrier, referenceConfig, receiverConfig, ...
                integrationContext, specification)
            arguments
                transportBlocks
                assignment (1,1) sixgr.pdsch.PDSCHSchedulingAssignment
                resourcePlan (1,1) sixgr.pdsch.PDSCHResourcePlan
                carrier (1,1) nrCarrierConfig
                referenceConfig (1,1) ...
                    sixgr.pdsch.PDSCHReferenceSignalConfig
                receiverConfig (1,1) struct
                integrationContext (1,1) struct
                specification (1,1) struct
            end

            data = assignment.toStruct();
            tbCells = sixgr.pdsch.PDSCHMultiTRPExecutor. ...
                normalizeTransportBlocks( ...
                    transportBlocks, double(data.NumCodewords));
            actualTBIdentity = sixgr.pdsch.PDSCHMultiTRPExecutor. ...
                transportBlockDigest(tbCells);
            declaredTBIdentity = "";
            if isfield(specification, "TBIdentityDigest")
                declaredTBIdentity = string( ...
                    specification.TBIdentityDigest);
            end
            if ~isscalar(declaredTBIdentity) ...
                    || declaredTBIdentity ~= actualTBIdentity
                error("sixgr:pdsch:MultiTRPTransportBlockIdentityMismatch", ...
                    "Multi-TRP TBIdentityDigest must be the digest of the " + ...
                    "transport blocks submitted to canonical transmission.");
            end
            if ~isfield(specification, "TRPs") ...
                    || ~isstruct(specification.TRPs) ...
                    || isempty(specification.TRPs)
                error("sixgr:pdsch:IncompleteMultiTRPSpecification", ...
                    "Multi-TRP execution requires a nonempty TRP vector.");
            end

            firstBundle = specification.TRPs(1).PrecoderBundle;
            binding = sixgr.pdsch.PDSCHIntegrationValidator.bind( ...
                assignment, integrationContext, firstBundle);
            plan = sixgr.pdsch.PDSCHIntegrationValidator. ...
                transmissionOccasions(assignment, binding, specification);
            if any([plan.Occasions.AbsoluteSlot] ...
                    ~= double(data.PDSCHAbsoluteSlot))
                error("sixgr:pdsch:UnsupportedMultiTRPSlotOffsetExecution", ...
                    "Canonical bounded repetition currently supports " + ...
                    "same-slot TRP occasions only; a later slot requires " + ...
                    "a distinct immutable scheduling assignment.");
            end

            nOccasions = numel(plan.Occasions);
            nCodewords = double(data.NumCodewords);
            transmitters = cell(1, nOccasions);
            receivers = cell(1, nOccasions);
            bindings = cell(1, nOccasions);
            llrPerOccasion = cell(nOccasions, nCodewords);
            for occasionIndex = 1:nOccasions
                occasion = plan.Occasions(occasionIndex);
                bundle = occasion.PrecoderBundle;
                bindings{occasionIndex} = ...
                    sixgr.pdsch.PDSCHIntegrationValidator.bind( ...
                        assignment, integrationContext, bundle);
                transmitterInput = tbCells;
                if nCodewords == 1
                    transmitterInput = tbCells{1};
                end
                tx = sixgr.pdsch.PDSCHTransmitter( ...
                    transmitterInput, assignment, resourcePlan, carrier, ...
                    referenceConfig, "PrecoderBundle", bundle, ...
                    "IntegrationContext", integrationContext);
                waveform = double(occasion.PowerScaling) * tx.Waveform;
                rx = sixgr.pdsch.PDSCHReceiver( ...
                    waveform, assignment, resourcePlan, carrier, ...
                    referenceConfig, receiverConfig, ...
                    "CodingPlans", tx.CodingPlans, ...
                    "PrecoderBundle", bundle, ...
                    "IntegrationContext", integrationContext);
                if tx.Source ~= ...
                        "explicit_pdsch_dlsch_production_chain" ...
                        || rx.Source ~= ...
                        "explicit_pdsch_dlsch_production_receiver"
                    error("sixgr:pdsch:MultiTRPNoncanonicalOccasion", ...
                        "Every multi-TRP occasion must use canonical TX/RX.");
                end
                if numel(rx.DescrambledLLR) ~= nCodewords
                    error("sixgr:pdsch:MultiTRPLLRLayoutMismatch", ...
                        "Canonical receiver codeword count changed.");
                end
                for codeword = 1:nCodewords
                    llrPerOccasion{occasionIndex, codeword} = ...
                        double(rx.DescrambledLLR{codeword}(:));
                end
                transmitters{occasionIndex} = tx;
                receivers{occasionIndex} = rx;
            end

            codingPlans = transmitters{1}.CodingPlans;
            if ~iscell(codingPlans)
                codingPlans = {codingPlans};
            end
            combinedLLR = cell(1, nCodewords);
            combinedDecode = cell(1, nCodewords);
            crcPass = false(1, nCodewords);
            recoveredTB = cell(1, nCodewords);
            maxIterations = double(sixgr.util.structGet( ...
                receiverConfig, "MaxIterations", 12));
            algorithm = string(sixgr.util.structGet( ...
                receiverConfig, "Algorithm", "Normalized min-sum"));
            for codeword = 1:nCodewords
                observations = reshape( ...
                    llrPerOccasion(:, codeword), 1, []);
                combinedLLR{codeword} = ...
                    sixgr.pdsch.PDSCHIntegrationValidator. ...
                        combineOccasionLLR(observations, plan);
                combinedDecode{codeword} = sixgr.pdsch.DLSCHDecoder( ...
                    combinedLLR{codeword}, ...
                    "CodingPlan", codingPlans{codeword}, ...
                    "MaxIterations", maxIterations, ...
                    "Algorithm", algorithm);
                crcPass(codeword) = ...
                    logical(combinedDecode{codeword}.CRCPass);
                recoveredTB{codeword} = int8( ...
                    combinedDecode{codeword}.TransportBlock(:));
            end

            exactTB = true;
            for codeword = 1:nCodewords
                exactTB = exactTB && ...
                    isequal(recoveredTB{codeword}, tbCells{codeword});
            end
            result = struct( ...
                "ContractVersion", "CanonicalPDSCHMultiTRPExecution/v1", ...
                "Plan", plan, ...
                "AssignmentId", assignment.AssignmentId, ...
                "TBIdentityDigest", actualTBIdentity, ...
                "Bindings", {bindings}, ...
                "Transmitters", {transmitters}, ...
                "Receivers", {receivers}, ...
                "PerOccasionDescrambledLLR", {llrPerOccasion}, ...
                "CombinedRateMatchedLLR", {combinedLLR}, ...
                "CombinedDecode", {combinedDecode}, ...
                "TransportBlocks", {recoveredTB}, ...
                "CRCPassPerCodeword", crcPass, ...
                "CRCPass", all(crcPass), ...
                "ExactTransportBlockRecovery", logical(exactTB), ...
                "ActualCanonicalOccasionCount", nOccasions, ...
                "LLRSource", "PDSCHReceiver.DescrambledLLR", ...
                "CombinationRule", plan.CombinationRule, ...
                "Source", ...
                    "canonical_pdsch_two_trp_noncoherent_repetition");
        end

        function digest = transportBlockDigest(transportBlocks)
            if ~iscell(transportBlocks)
                transportBlocks = {transportBlocks};
            end
            records = repmat(struct( ...
                "CodewordIndex", 0, "BitCount", 0, "Bits", ""), ...
                1, numel(transportBlocks));
            for codeword = 1:numel(transportBlocks)
                bits = double(transportBlocks{codeword}(:));
                if isempty(bits) || any(~ismember(bits, [0 1]))
                    error("sixgr:pdsch:InvalidMultiTRPTransportBlock", ...
                        "Each multi-TRP transport block must be binary.");
                end
                records(codeword).CodewordIndex = codeword - 1;
                records(codeword).BitCount = numel(bits);
                records(codeword).Bits = char('0' + bits.');
            end
            bytes = uint8(unicode2native( ...
                jsonencode(records), "UTF-8"));
            digest = string(sixgr.util.sha256Hex(bytes));
        end
    end

    methods (Static, Access = private)
        function blocks = normalizeTransportBlocks(value, count)
            if count == 1 && ~iscell(value)
                blocks = {value};
            elseif iscell(value)
                blocks = reshape(value, 1, []);
            else
                error("sixgr:pdsch:MultiTRPCodewordCountMismatch", ...
                    "Multiple codewords require one transport block per cell.");
            end
            if numel(blocks) ~= count
                error("sixgr:pdsch:MultiTRPCodewordCountMismatch", ...
                    "Transport-block count differs from assignment codewords.");
            end
            for codeword = 1:count
                bits = double(blocks{codeword}(:));
                if isempty(bits) || any(~ismember(bits, [0 1]))
                    error("sixgr:pdsch:InvalidMultiTRPTransportBlock", ...
                        "Each multi-TRP transport block must be binary.");
                end
                blocks{codeword} = int8(bits);
            end
        end
    end
end
