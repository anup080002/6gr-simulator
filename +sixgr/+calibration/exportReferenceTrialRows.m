function T=exportReferenceTrialRows(folder,caseID,role,attempt,curveID,key)
%EXPORTREFERENCETRIALROWS Retain a row-to-waveform proof for SLS packaging.
role=string(role); caseID=string(caseID); curveID=string(curveID);
assert(any(role==["reference","reference_validation"]), ...
    'sixgr:calibration:SourceRole','Only independently executed AWGN reference roles belong in the BLER lookup.');
m=load(fullfile(folder,'campaign.mat'),'p','cases','identity');
caseIndex=find(string({m.cases.ID})==caseID);
assert(isscalar(caseIndex),'sixgr:calibration:SourceCase','Unknown physical calibration case.');
assert(string(key.Direction)==m.cases(caseIndex).Direction, ...
    'sixgr:calibration:SourceKey','SLS key direction differs from the executed waveform.');
validateattributes(attempt,{'numeric'},{'scalar','integer','>=',1,'<=',numel(m.p.rv_sequence)});
[~,axis]=sixgr.calibration.historyGrid(m.p,role); na=numel(axis);
keySHA=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(key),'UTF-8'))));
files=dir(fullfile(folder,'episodes','episode_*.mat')); rows=cell(0,1);
for k=1:numel(files)
    path=fullfile(files(k).folder,files(k).name);
    sixgr.calibration.verifyEpisodeFile(path);
    x=load(path,'episode'); e=x.episode;
    if e.CaseID~=caseID || e.Role~=role || numel(e.Attempts)<attempt, continue; end
    assert(e.CampaignIdentity==m.identity && e.Direction==key.Direction, ...
        'sixgr:calibration:SourceIdentity','Mixed waveform campaign or direction.');
    [present,digits]=ismember(e.PlannedSNRHistory_dB(1:attempt),axis);
    assert(all(present),'sixgr:calibration:History','AWGN source history is outside the retained grid.');
    gridIndex=1+sum((digits-1).*na.^(0:attempt-1));
    a=e.Attempts(attempt);
    assert(a.Attempt==attempt && a.RV==m.p.rv_sequence(attempt) && ...
        a.WaveformExecuted && logical(a.PriorAttemptsFailed)==(attempt>1), ...
        'sixgr:calibration:SourceAttempt','Invalid physical HARQ sequence.');
    rows{end+1,1}=struct('CurveID',curveID,'GridPointIndex',gridIndex, ...
        'TrialID',e.EpisodeID+"_"+attempt,'AttemptIndex',attempt, ...
        'CRCError',logical(a.CRCError),'PriorAttemptsFailed',logical(a.PriorAttemptsFailed), ...
        'WaveformExecuted',true,'CalibrationKeySHA256',keySHA, ...
        'EpisodePath',string(fullfile('episodes',files(k).name)), ...
        'EpisodeSHA256',sixgr.csi.studyFileSHA256(path), ...
        'EpisodeID',e.EpisodeID,'CampaignIdentity',m.identity,'CaseID',caseID, ...
        'TransportBlockSHA256',a.TransportBlockSHA256, ...
        'NoiseSeed',double(a.NoiseSeed),'ChannelSeed',double(a.ChannelSeed)); %#ok<AGROW>
end
assert(~isempty(rows),'sixgr:calibration:SourcePopulation','No executed AWGN conditional trials for this curve.');
T=struct2table(vertcat(rows{:}));
end
