function [feature,allocation] = extractAppliedSpatialSINR(diagnostic, receiverType)
%EXTRACTAPPLIEDSPATIALSINR Diagonal applied-channel calibration predictor.
% Model prediction from executed waveform evidence, not measured SINR.
arguments
    diagnostic (1,1) struct
    receiverType (1,1) string {mustBeMember(receiverType,["lmmse","zf"])}
end
[metadata,allocation,channel]=sixgr.calibration.resolveAppliedSpatialEvidence(diagnostic);
estimate=sixgr.system.abstraction.evaluateSpatialSINR(channel, ...
    allocation.NormalizedPrecoder,allocation.TotalPowerPerRE, ...
    metadata.GridNoiseVariance*eye(allocation.NumRx),receiverType);
assert(all(isfinite(estimate.SINRLinear),'all') && all(estimate.SINRLinear>=0,'all'), ...
    'sixgr:calibration:SpatialFeatureNumerics','Applied-channel feature contains invalid linear SINR.');
feature=struct('SINRLinear',estimate.SINRLinear, ...
    'SINRSource',"applied_channel_per_data_re_per_layer_"+receiverType+"_not_receiver_measurement", ...
    'DataRECount',metadata.DataRECount,'PerLayerSymbolEnergy',metadata.PerLayerSymbolEnergy, ...
    'GridNoiseVariance',metadata.GridNoiseVariance, ...
    'InterLayerInterferencePower',estimate.InterLayerInterferencePower, ...
    'FeatureRole',metadata.FeatureRole,'SourceClassification',metadata.SourceClassification, ...
    'WaveformBacked',metadata.WaveformBacked);
end
