function assertGrantSourceIdentity(retained)
%ASSERTGRANTSOURCEIDENTITY Never reuse curves across unqualified source changes.
current=sixgr.calibration.grantSourceIdentity();
assert(isequaln(retained,current), ...
    'sixgr:calibration:GrantSourceChanged', ...
    ['Calibration source/catalog/MATLAB/toolbox identity differs from the active implementation. ' ...
     'Use the frozen execution environment or collect and validate a new package.']);
end
