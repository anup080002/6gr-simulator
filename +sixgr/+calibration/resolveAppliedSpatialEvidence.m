function [metadata,allocation,channel]=resolveAppliedSpatialEvidence(diagnostic)
%RESOLVEAPPLIEDSPATIALEVIDENCE Validate executed symbols/resources/power once.
% This resolves no detector and reports no SINR. Finite and diagonal channel
% models share these input checks, not each other's numerical receiver.
arguments
    diagnostic (1,1) struct
end
assert(isfield(diagnostic,'Tx') && isfield(diagnostic,'TrueChannelGrid') && ...
    isfield(diagnostic,'NoiseInfo'), ...
    'sixgr:calibration:SpatialFeatureEvidence', ...
    'The executed Tx, per-RE channel and grid-noise evidence are required.');
tx=diagnostic.Tx;
if isfield(tx,'PDSCHLayerIndices')
    indices=double(tx.PDSCHLayerIndices(:));
    symbols=double(tx.PDSCHLayerSymbols(:));
    layerSymbols=double(tx.PDSCHLayerSymbols);
    portSymbols=double(tx.PDSCHPortSymbols);
    rankValue=double(tx.PDSCH.NumLayers);
elseif isfield(tx,'PUSCHLayerIndices')
    assert(~logical(tx.PUSCH.TransformPrecoding), ...
        'sixgr:calibration:SpatialFeatureWaveform', ...
        'The CP-OFDM spatial feature cannot represent transform-precoded PUSCH.');
    indices=double(tx.PUSCHLayerIndices(:));
    symbols=double(tx.PUSCHLayerSymbols(:));
    layerSymbols=double(tx.PUSCHLayerSymbols);
    portSymbols=double(tx.PUSCHPortSymbols);
    rankValue=double(tx.PUSCH.NumLayers);
else
    error('sixgr:calibration:SpatialFeatureEvidence', ...
        'The executed data-layer indices are unavailable.');
end
h=double(diagnostic.TrueChannelGrid);
nSubcarriers=size(h,1); nSymbols=size(h,2);
nRx=size(h,3); nTx=size(h,4);
planeSize=nSubcarriers*nSymbols;
assert(rankValue==fix(rankValue) && rankValue>=1 && ...
    rankValue<=min(nRx,nTx) && ~isempty(indices) && ...
    numel(indices)==numel(symbols) && ...
    all(isfinite(indices)) && all(indices==fix(indices)) && ...
    all(indices>=1 & indices<=planeSize*rankValue) && ...
    all(isfinite(h),'all') && all(isfinite(symbols)), ...
    'sixgr:calibration:SpatialFeatureDimensions', ...
    'Executed layer indices, symbols or channel dimensions disagree.');
layer=floor((indices-1)/planeSize)+1;
resource=mod(indices-1,planeSize)+1;
base=unique(resource,'stable');
energy=zeros(1,rankValue);
for j=1:rankValue
    selected=layer==j;
    assert(sum(selected)==numel(base) && ...
        isequal(resource(selected),base), ...
        'sixgr:calibration:SpatialFeatureMapping', ...
        'Every layer-symbol row must map to the same ordered data RE.');
    energy(j)=mean(abs(symbols(selected)).^2);
end
assert(all(isfinite(energy)) && all(energy>0), ...
    'sixgr:calibration:SpatialFeatureEnergy', ...
    'Executed layer symbols must have positive finite mean energy.');
prec=tx.PrecodeInfo;
assert(~logical(sixgr.util.structGet(prec,'HybridElementDomainApplied',false)) && ...
    isfield(prec,'MatrixPorts'), ...
    'sixgr:calibration:SpatialFeaturePrecoder', ...
    'The executed constant logical-port precoder is required.');
w=double(prec.MatrixPorts);
assert(isequal(size(w),[nTx rankValue]) && all(isfinite(w),'all'), ...
    'sixgr:calibration:SpatialFeaturePrecoder', ...
    'Applied precoder dimensions must match Tx ports and layers.');
if isfield(prec,'MatrixPortsPerPRG') && ~isempty(prec.MatrixPortsPerPRG)
    pages=double(prec.MatrixPortsPerPRG);
    assert(size(pages,1)==nTx && size(pages,2)==rankValue && ...
        all(abs(pages-repmat(w,1,1,size(pages,3)))<=1e-12,'all'), ...
        'sixgr:calibration:SpatialFeaturePRG', ...
        'PRG-varying precoders require an exact RE-to-PRG feature map.');
end
assert(isequal(size(layerSymbols),[numel(base) rankValue]) && ...
    isequal(size(portSymbols),[numel(base) nTx]), ...
    'sixgr:calibration:SpatialFeatureMapping', ...
    'Executed layer and port symbol matrices must match the data RE map.');
expectedPorts=layerSymbols*w.';
scale=max(1,norm(portSymbols,'fro'));
assert(norm(portSymbols-expectedPorts,'fro')<=1e-9*scale, ...
    'sixgr:calibration:SpatialFeaturePrecoder', ...
    'The claimed precoder does not reproduce the executed port symbols.');
n0=double(diagnostic.NoiseInfo.GridNoiseVariance);
assert(isscalar(n0) && isfinite(n0) && n0>0, ...
    'sixgr:calibration:SpatialFeatureNoise', ...
    'Executed positive grid-domain noise variance is required.');
% The layer-symbol covariance is taken from the actual coded waveform.
% Normalizing W for the shared spatial evaluator and passing its squared
% Frobenius norm as total power exactly reconstructs H*W*sqrt(E_layer).
weighted=w*diag(sqrt(energy));
totalPower=sum(abs(weighted).^2,'all');
assert(isfinite(totalPower) && totalPower>0, ...
    'sixgr:calibration:SpatialFeaturePrecoder', ...
    'Applied precoder has zero or nonfinite power.');
selectedGrid=reshape(h,[planeSize nRx nTx]);
channel=permute(selectedGrid(base,:,:),[2 3 1]);
metadata=struct('DataRECount',numel(indices),'PerLayerSymbolEnergy',energy, ...
    'GridNoiseVariance',n0,'FeatureRole',"calibration_predictor_not_receiver_measurement", ...
    'SourceClassification',"applied_channel_predictor_from_executed_waveform_not_receiver_measurement", ...
    'WaveformBacked',true);
allocation=struct('Coordinates0Based',[mod(base-1,nSubcarriers) floor((base-1)/nSubcarriers)], ...
    'NormalizedPrecoder',weighted/sqrt(totalPower),'TotalPowerPerRE',totalPower, ...
    'NumRx',nRx,'NumTx',nTx);
end
