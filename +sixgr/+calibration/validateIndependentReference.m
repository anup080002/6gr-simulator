function report=validateIndependentReference(reference,heldout,policy)
%VALIDATEINDEPENDENTREFERENCE Check measured AWGN conditional BLER on a
% separate frozen waveform population at identical SNR-history points.
assert(isequal(size(reference.TrialCount),size(heldout.TrialCount)) && ...
    isequal(size(reference.ErrorCount),size(heldout.ErrorCount)) && ...
    isequal(size(reference.TrialCount),size(reference.ErrorCount)), ...
    'sixgr:calibration:ReferenceValidationGrid','AWGN fit and validation grids must match.');
supported=true(size(reference.TrialCount));
if isfield(reference,'SupportedMask'), supported=logical(reference.SupportedMask); end
assert(isequal(size(supported),size(reference.TrialCount)) && any(supported,'all'), ...
    'sixgr:calibration:ReferenceValidationGrid','No supported reference cells exist.');
assert(all(reference.TrialCount(supported)>=policy.minimum_conditional_trials) && ...
    all(heldout.TrialCount(supported)>=policy.minimum_conditional_trials) && ...
    all(reference.ErrorCount>=0 & reference.ErrorCount<=reference.TrialCount,'all') && ...
    all(heldout.ErrorCount>=0 & heldout.ErrorCount<=heldout.TrialCount,'all'), ...
    'sixgr:calibration:ReferenceValidationPopulation', ...
    'Both AWGN populations must contain sufficient actual conditional attempts.');
counts=numel(reference.TrialCount); upperBound=NaN(size(reference.TrialCount));
for k=1:counts
    if ~supported(k), continue; end
    [a,b]=sixgr.lls.stats.wilsonInterval(double(reference.ErrorCount(k)), ...
        double(reference.TrialCount(k)),policy.confidence_level);
    [c,d]=sixgr.lls.stats.wilsonInterval(double(heldout.ErrorCount(k)), ...
        double(heldout.TrialCount(k)),policy.confidence_level);
    upperBound(k)=max(b-c,d-a);
end
report=struct('Schema',"sixgr.independent_awgn_reference_validation/v1", ...
    'MaximumAbsoluteBLERDifferenceBound',max(upperBound(supported)), ...
    'PointwiseAbsoluteBLERDifferenceUpperBound',upperBound, ...
    'Passed',all(upperBound(supported)<=policy.maximum_validation_absolute_bler_error), ...
    'PrimaryStudyAccepted',false);
end
