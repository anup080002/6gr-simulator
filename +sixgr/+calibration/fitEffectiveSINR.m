function result=fitEffectiveSINR(reference,fit,validation,policy)
% Fit EESM beta to waveform CRCs against retained AWGN conditional BLER.
% Validation never chooses beta. Neither fitting nor this report certifies
% complete physical-key coverage or installs a production SLS calibration.
required=["TrialID","NoiseSeed","ChannelSeed","CRCError","SINRHistory","GroupID","ConfigurationSHA256"];
assert(istable(fit) && istable(validation) && ...
    all(ismember(required,string(fit.Properties.VariableNames))) && ...
    all(ismember(required,string(validation.Properties.VariableNames))), ...
    'sixgr:calibration:FittingSchema','Retain trial IDs, independent seeds, CRC and per-RE history.');
assert(all(string(fit.ConfigurationSHA256)==string(reference.ConfigurationSHA256)) && ...
    all(string(validation.ConfigurationSHA256)==string(reference.ConfigurationSHA256)), ...
    'sixgr:calibration:FittingKey','DL/UL, allocation, coding and receiver identity must match their reference.');
assert(isempty(intersect(string(fit.TrialID),string(validation.TrialID))) && ...
    isempty(intersect([fit.NoiseSeed;fit.ChannelSeed],[validation.NoiseSeed;validation.ChannelSeed])), ...
    'sixgr:calibration:ValidationLeakage','Fit and validation reuse trial identities or physical random streams.');
assert(numel(unique(string(fit.TrialID)))==height(fit) && ...
    numel(unique(string(validation.TrialID)))==height(validation), ...
    'sixgr:calibration:ValidationLeakage','Repeated trial identities within a population.');
for rows={fit,validation}
    r=rows{1};
    assert(height(r)>=policy.minimum_conditional_trials && all(ismember(double(r.CRCError),[0 1])), ...
        'sixgr:calibration:FittingPopulation','Insufficient or invalid physical populations.');
end
supported=true(size(reference.TrialCount));
if isfield(reference,'SupportedMask'), supported=logical(reference.SupportedMask); end
assert(isequal(size(supported),size(reference.TrialCount)) && any(supported,'all') && ...
    all(reference.TrialCount(supported)>=policy.minimum_conditional_trials) && ...
    all(reference.ErrorCount>=0 & reference.ErrorCount<=reference.TrialCount,'all'), ...
    'sixgr:calibration:ReferencePopulation','Incomplete conditional AWGN reference grid.');
axes=reference.SINRAxes_dB; nAttempts=numel(axes);
for a=1:nAttempts
    assert(isvector(axes{a}) && numel(axes{a})>=2 && all(isfinite(axes{a})) && all(diff(axes{a})>0), ...
        'sixgr:calibration:ReferenceGrid','Invalid reference axis.');
end
shape=cellfun(@numel,axes); if isscalar(shape), shape=[shape 1]; end
assert(isequal(size(reference.TrialCount),shape) && isequal(size(reference.ErrorCount),shape), ...
    'sixgr:calibration:ReferenceGrid','Counts must span the Cartesian SINR-history grid.');
prob=NaN(size(reference.TrialCount));
prob(supported)=double(reference.ErrorCount(supported))./double(reference.TrialCount(supported));
betas=exp(linspace(log(policy.beta_linear_bounds(1)),log(policy.beta_linear_bounds(2)),policy.beta_log_grid_count));
loss=Inf(size(betas));
for k=1:numel(betas)
    predicted=localPredict(fit.SINRHistory,betas(k),axes,prob);
    if any(~isfinite(predicted)), continue; end % no extrapolation or row removal
    bounded=min(1-eps,max(eps,predicted)); % numerical log guard, not output probabilities
    loss(k)=-mean(double(fit.CRCError).*log(bounded)+(1-double(fit.CRCError)).*log1p(-bounded));
end
[best,index]=min(loss);
assert(isfinite(best),'sixgr:calibration:ReferenceCoverage','Reference domain cannot cover every fit observation.');
assert(index>1 && index<numel(betas) && ...
    max(loss(isfinite(loss)))-best>=policy.minimum_beta_objective_contrast, ...
    'sixgr:calibration:UnidentifiableBeta','Beta is unidentifiable or reaches a search bound; do not invent a value.');
beta=betas(index);
prediction=localPredict(validation.SINRHistory,beta,axes,prob);
assert(all(isfinite(prediction)), ...
    'sixgr:calibration:ValidationCoverage','Held-out features leave the fitted reference domain.');
observed=mean(double(validation.CRCError)); predicted=mean(prediction);
[lo,hi]=sixgr.lls.stats.wilsonInterval(sum(validation.CRCError),height(validation),policy.confidence_level);
groups=unique(string(validation.GroupID)); checks=cell(numel(groups),1);
assert(all(ismember(groups,string(fit.GroupID))) && all(ismember(string(fit.GroupID),groups)), ...
    'sixgr:calibration:ValidationCoverage','Fit and validation must cover the same configured populations.');
for k=1:numel(groups)
    ix=string(validation.GroupID)==groups(k); n=sum(ix); errors=sum(validation.CRCError(ix));
    [lower,upper]=sixgr.lls.stats.wilsonInterval(errors,n,policy.confidence_level);
    checks{k}=struct('GroupID',groups(k),'Trials',n,'ObservedBLER',errors/n, ...
        'PredictedBLER',mean(prediction(ix)),'CILower',lower,'CIUpper',upper, ...
        'Pass',n>=policy.minimum_conditional_trials && ...
        sum(string(fit.GroupID)==groups(k))>=policy.minimum_conditional_trials && ...
        abs(mean(prediction(ix))-errors/n)<=policy.maximum_validation_absolute_bler_error && ...
        (upper-lower)/2<=policy.maximum_wilson_half_width);
end
checks=vertcat(checks{:}); passed=all([checks.Pass]);
result=struct('Schema',"sixgr.eesm_fit/v1",'BetaLinear',beta,'FitNegativeLogLikelihood',best, ...
    'BetaCandidates',betas,'FitObjective',loss,'FitTrials',height(fit), ...
    'ValidationTrials',height(validation),'ValidationObservedBLER',observed, ...
    'ValidationPredictedBLER',predicted,'ValidationCILower',lo,'ValidationCIUpper',hi, ...
    'ValidationPredictions',prediction,'FittingPassed',passed,'PrimaryStudyAccepted',false, ...
    'ValidationGroups',checks,'ConfigurationSHA256',reference.ConfigurationSHA256, ...
    'Method',"EESM_frozen_log_grid_binomial_likelihood_fit_only", ...
    'SourceClassification',"fitted_link_abstraction_not_waveform_truth");
end
function predictions=localPredict(histories,beta,axes,prob)
n=numel(histories); na=numel(axes); effective=zeros(n,na);
for i=1:n
    h=histories{i};
    assert(iscell(h) && numel(h)==na,'sixgr:calibration:FeatureHistory','One resource vector per attempt is required.');
    for a=1:na
        g=double(h{a}(:));
        assert(~isempty(g) && all(isfinite(g)) && all(g>=0), ...
            'sixgr:calibration:FeatureHistory','SINR must be retained finite nonnegative linear per-RE values.');
        minimum=min(g);
        value=minimum-beta*log(mean(exp(-(g-minimum)/beta)));
        effective(i,a)=10*log10(value);
    end
end
if na==1
    predictions=interp1(axes{1},prob(:),effective(:,1),'linear',NaN);
else
    queries=num2cell(effective,1);
    predictions=interpn(axes{:},prob,queries{:},'linear',NaN);
end
end
