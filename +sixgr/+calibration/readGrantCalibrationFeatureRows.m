function [rows,proof]=readGrantCalibrationFeatureRows(folder,key,attempt)
%READGRANTCALIBRATIONFEATUREROWS Verify frozen-grant populations before fitting.
% The joint CSV is a view, not the authority. Rebuild features and keys from
% sealed waveform episodes and the sealed plan. No statistical acceptance,
% reference-domain extrapolation or production installation happens here.
arguments
    folder (1,1) string
    key (1,1) struct
    attempt (1,1) double {mustBeInteger,mustBePositive}
end
assert(~isfile(fullfile(folder,'source_change_failure.json')), ...
    'sixgr:calibration:GrantSourceChanged', ...
    'A source-change quarantine cannot supply calibration features.');
manifest=fullfile(folder,'campaign.mat');
sixgr.calibration.verifyEpisodeFile(manifest);
m=load(manifest);
assert(all(isfield(m,{'cfg','plan','sources','identity'})), ...
    'sixgr:calibration:GrantFeatureManifest','Missing frozen campaign fields.');
storageMode=string(sixgr.util.structGet(m,'storageMode','raw'));
assert(isscalar(storageMode) && ismember(storageMode,["raw","lossless_path_gains_xor_v1"]), ...
    'sixgr:calibration:GrantFeatureManifest','Invalid frozen evidence storage policy.');
identityValue=struct('Schema',"sixgr.grant_collection/v1", ...
    'Config',m.cfg,'Plan',m.plan,'Sources',m.sources);
if storageMode~="raw", identityValue.EvidenceStorage=storageMode; end
assert(string(m.identity)==localHash(identityValue), ...
    'sixgr:calibration:GrantFeatureManifest','Frozen campaign identity is inconsistent.');
ids=string({m.plan.EpisodeID}); roles=string({m.plan.Role});
assert(numel(unique(ids))==numel(ids) && all(strlength(strtrim(ids))>0) && ...
    all(ismember(roles,["fit","validation"])) && all(ismember(["fit","validation"],roles)), ...
    'sixgr:calibration:GrantFeatureManifest','Require independent, identifiable fit and validation plans.');
seeds=[]; evolutions=strings(numel(m.plan),1);
for k=1:numel(m.plan)
    s=m.plan(k).Seeds;
    [streams,evolutions(k)]=sixgr.system.waveform.validateGrantCalibrationSeeds(s,numel(m.plan(k).Grants));
    seeds=[seeds;streams]; %#ok<AGROW>
end
assert(numel(unique(evolutions))==1,'sixgr:calibration:GrantFeatureIndependence', ...
    'Do not pool different channel-history assumptions.');
assert(all(isfinite(seeds)) && all(seeds>=0 & seeds<=2^32-1 & seeds==fix(seeds)) && ...
    numel(unique(seeds))==numel(seeds), ...
    'sixgr:calibration:GrantFeatureIndependence','Component seeds must not repeat across episodes or roles.');
keySHA=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(key),'UTF-8'))));
records=struct([]); present=0; missing=strings(0,1); historyOffsets=[];
for k=1:numel(m.plan)
    relative="episodes/"+localHash(ids(k))+".mat";
    path=fullfile(folder,relative);
    if ~isfile(path), missing(end+1,1)=ids(k); continue; end %#ok<AGROW>
    sixgr.calibration.verifyEpisodeFile(path);
    saved=load(path,'episodeID','role','collectionIdentity','episode');
    assert(string(saved.episodeID)==ids(k) && string(saved.role)==roles(k) && ...
        string(saved.collectionIdentity)==string(m.identity), ...
        'sixgr:calibration:GrantFeatureEpisode','Episode does not belong to the frozen collection.');
    e=sixgr.calibration.decodeGrantEpisodeStorage(saved.episode,storageMode);
    p=m.plan(k); n=numel(e.Attempts); present=present+1;
    assert(string(e.Schema)=="sixgr.frozen_grant_calibration_episode/v1" && ...
        isequaln(e.ResolvedConfig,m.cfg) && isequaln(e.PlannedGrants,p.Grants) && ...
        isequaln(e.SeedPlan,p.Seeds) && isequaln(e.PlannedSNRdB,p.SNRdB) && ...
        e.WaveformBacked && ~e.CalibrationQualified && ...
        string(e.ChannelEvolution)==evolutions(k) && ...
        n>=1 && n<=numel(p.Grants) && numel(e.Captures)==n && numel(e.Replays)==n && ...
        numel(e.CalibrationBindings)==n && numel(e.SpatialPredictorFeatures)==n, ...
        'sixgr:calibration:GrantFeatureEpisode','Raw episode differs from its execution plan or schema.');
    assert(all(ismember(double([e.Attempts.CRCError]),[0 1])) && ...
        all([e.Attempts(1:end-1).CRCError]) && ...
        logical(e.Delivered)==~logical(e.Attempts(end).CRCError) && ...
        (e.Delivered || n==numel(p.Grants)), ...
        'sixgr:calibration:GrantFeatureHARQ','Episode must stop on success and retain only causal retries.');
    expectedStop="attempt_budget_exhausted"; if e.Delivered, expectedStop="crc_success"; end
    assert(string(e.StopReason)==expectedStop,'sixgr:calibration:GrantFeatureHARQ','Incorrect stopping evidence.');
    bitStream=RandStream('mt19937ar','Seed',double(p.Seeds.Bits));
    expectedBits=int8(randi(bitStream,[0 1],p.Grants{1}.TBSBits,1));
    bitSHA=string(sixgr.util.sha256Hex(uint8(expectedBits)));
    assert(isequal(expectedBits,e.OriginalTransportBlock), ...
        'sixgr:calibration:GrantFeaturePayload','Original bits do not match the independent planned payload stream.');
    history=cell(1,n); keys=cell(1,n);
    for j=1:n
        a=e.Attempts(j); c=e.Captures{j}; r=e.Replays{j}; g=p.Grants{j};
        map=sixgr.system.abstraction.scheduledDataREMap(m.cfg,g,g.ScheduledAbsoluteSlot);
        expectedTime=0;
        if evolutions(k)=="persistent_link_absolute_slot"
            expectedTime=sixgr.system.waveform.resolveReplayChannelTime( ...
                m.cfg,g,'ScheduledAbsoluteSlot',[]);
        end
        assert(double(sixgr.util.structGet(a,'ChannelInitialTime_s',0))==expectedTime && ...
            double(sixgr.util.structGet(r,'ReplayChannelInitialTime_s',0))==expectedTime && ...
            double(sixgr.util.structGet(c.Propagation,'ChannelInitialTime_s',0))==expectedTime, ...
            'sixgr:calibration:GrantFeatureChannelTime', ...
            'Executed fading time must match the declared history and frozen grant clock.');
        assert(a.Attempt==j && a.PriorAttemptsFailed==(j>1) && ...
            a.RV==g.RV && a.ScheduledAbsoluteSlot0==g.ScheduledAbsoluteSlot && ...
            a.ConfiguredSNRdB==p.SNRdB(j) && a.NoiseSeed==p.Seeds.Noise(j) && ...
            a.ChannelSeed==p.Seeds.Channel(j) && a.BitsSeed==p.Seeds.Bits && ...
            a.ControlNoiseSeed==p.Seeds.ControlNoise(j) && a.RFGlobalStreamSeed==p.Seeds.RF(j) && ...
            a.WaveformExecuted && r.WaveformReplayExecuted && a.CRCError==r.CRCError && ...
            a.CRCError==any(logical(c.Receiver.CRCError)) && ...
            (j==1 || (r.HARQSoftCombiningApplied && r.HARQSoftBufferPriorAvailable)) && ...
            a.TransportBlockSHA256==bitSHA && r.TransmittedTransportBlockSHA256==bitSHA && ...
            isequal(int8(c.Transmitter.TransportBlock(:)),expectedBits) && ...
            a.TBSBits==g.TBSBits && c.Transmitter.TransportBlockSize==g.TBSBits && ...
            r.AWGNNoiseSeed==a.NoiseSeed && r.ReplayChannelSeed==a.ChannelSeed && ...
            a.DataREAllocationSHA256==map.AllocationIdentitySHA256 && ...
            c.ScheduledDataREMap.AllocationIdentitySHA256==map.AllocationIdentitySHA256, ...
            'sixgr:calibration:GrantFeatureAttempt','Decoded attempt, payload, seeds or frozen resources disagree.');
        checked=sixgr.system.waveform.bindCalibrationReceiverIdentity(c,m.cfg);
        assert(isequaln(checked.CalibrationReceiverIdentity,c.CalibrationReceiverIdentity), ...
            'sixgr:calibration:GrantFeatureReceiver','Retained receiver recipe differs from executed settings.');
        [keys{j},feature]=sixgr.system.waveform.extractGrantCalibrationBinding(checked);
        assert(a.CalibrationBindingAvailable && ...
            a.CalibrationKeySHA256==feature.CalibrationKeySHA256 && ...
            isequaln(keys{j},e.CalibrationBindings{j}) && ...
            isequaln(feature,e.SpatialPredictorFeatures{j}) && ...
            (j==1 || isequaln(keys{1},keys{j})), ...
            'sixgr:calibration:GrantFeatureBinding','Retained runtime key or predictor differs from reconstructed waveform evidence.');
        history{j}=feature.SINRLinear;
    end
    if n<attempt || ~isequaln(keys{attempt},key), continue; end
    offsets=double([e.Attempts(1:attempt).ScheduledAbsoluteSlot0]);
    offsets=offsets-offsets(1);
    if isempty(historyOffsets), historyOffsets=offsets; end
    assert(isequal(historyOffsets,offsets), ...
        'sixgr:calibration:GrantFeatureHistoryClock', ...
        'One conditional curve cannot silently pool different HARQ slot-gap histories.');
    a=e.Attempts(attempt);
    row=struct('TrialID',string(m.identity)+"_"+ids(k)+"_"+attempt, ...
        'Role',roles(k),'NoiseSeed',a.NoiseSeed,'ChannelSeed',a.ChannelSeed, ...
        'CRCError',logical(a.CRCError),'SINRHistory',{{history(1:attempt)}}, ...
        'ConfiguredSNRHistory_dB',{{double(p.SNRdB(1:attempt))}}, ...
        'RVSequence',{{double([e.Attempts(1:attempt).RV])}}, ...
        'HARQSlotOffsets0',{{offsets}}, ...
        'GroupID',string(jsonencode(p.SNRdB(1:attempt))), ...
        'ConfigurationSHA256',keySHA,'EpisodeID',ids(k),'Attempt',attempt, ...
        'EpisodeRelativePath',relative,'EpisodeSHA256',sixgr.csi.studyFileSHA256(path));
    if isempty(records), records=row; else, records(end+1)=row; end %#ok<AGROW>
end
rows=table(); if ~isempty(records), rows=struct2table(records); end
proof=struct('CollectionIdentity',string(m.identity),'MatchingRuntimeKeySHA256',keySHA, ...
    'PlannedEpisodes',numel(m.plan),'VerifiedEpisodes',present,'MissingEpisodes',missing, ...
    'AllPlannedEpisodesPresent',isempty(missing),'MatchingConditionalTrials',height(rows), ...
    'SourceClassification',"verified_executed_frozen_grant_waveform_features", ...
    'SourceIdentitySHA256',localHash(m.sources),'ComponentSeeds',seeds, ...
    'ChannelEvolution',evolutions(1), ...
    'HARQSlotOffsets0',historyOffsets, ...
    'CalibrationQualified',false,'PrimaryStudyAccepted',false);
end

function digest=localHash(value)
digest=string(sixgr.util.sha256Hex(uint8(unicode2native( ...
    jsonencode(sixgr.util.jsonSafeValue(value)),'UTF-8'))));
end
