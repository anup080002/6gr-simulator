function n=referencePairPlanningFloor(q)
%REFERENCEPAIRPLANNINGFLOOR Size independent AWGN cohorts at BLER 0.5.
% Two identical point estimates at the steep transition still fail the
% independent-reference check if their Wilson intervals are too wide.
% This is a planning floor, not a promise that observed cohorts will pass.
validateattributes(q.minimum_conditional_trials,{'numeric'}, ...
    {'scalar','integer','positive','finite'});
validateattributes(q.confidence_level,{'numeric'},{'scalar','>',0,'<',1});
validateattributes(q.maximum_wilson_half_width,{'numeric'}, ...
    {'scalar','>',0,'<',0.5});
validateattributes(q.maximum_validation_absolute_bler_error,{'numeric'}, ...
    {'scalar','>',0,'<',1});
z=sqrt(2)*erfcinv(1-double(q.confidence_level));
% At p=1/2, a Wilson interval has half-width z/(2*sqrt(n+z^2)).
% The bound between two identical independent intervals is twice that.
allowedWidth=min(double(q.maximum_validation_absolute_bler_error), ...
    2*double(q.maximum_wilson_half_width));
raw=(z/allowedWidth)^2-z^2;
assert(isfinite(raw) && raw<=flintmax, ...
    'sixgr:calibration:PopulationPlan', ...
    'Reference confidence policy requires an unrepresentable population.');
n=2*ceil(max(double(q.minimum_conditional_trials),max(0,raw))/2);
assert(n<=flintmax,'sixgr:calibration:PopulationPlan', ...
    'Reference population cannot be represented exactly.');
% Verify the implemented Wilson routine, not only the closed-form algebra.
[lo,hi]=sixgr.lls.stats.wilsonInterval(n/2,n,double(q.confidence_level));
assert((hi-lo)/2<=double(q.maximum_wilson_half_width)+1e-12 && ...
    hi-lo<=double(q.maximum_validation_absolute_bler_error)+1e-12, ...
    'sixgr:calibration:PopulationPlan', ...
    'Reference population fails its own independent validation policy.');
end
