function grants=buildGrantCalibrationAllocation(cfg,a)
%BUILDGRANTCALIBRATIONALLOCATION Exact planned allocations, not received DCI.
% Uses the production scheduler's resource/TBS materialization. Nothing here
% is a decoded observation or an adaptive scheduling/feedback qualification.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
c=sixgr.lls6g.config.readConfigFile(fullfile(root, ...
    'simulator','configs','schema','grant_calibration_campaign.yaml'));
fields=string(c.allocation_fields);
assert(isstruct(a) && isscalar(a) && all(isfield(a,cellstr(fields))) && ...
    all(ismember(string(fieldnames(a)),fields)), ...
    'sixgr:calibration:AllocationFields','Declare exactly the catalog allocation fields.');
direction=string(a.direction);
assert(isscalar(direction) && any(direction==["DL","UL"]) && ...
    string(a.control_assumption)==string(c.allocation_control_assumption), ...
    'sixgr:calibration:AllocationControl','Declare DL/UL and ideal_issued_grant; no physical DCI is claimed.');
for name=["rnti","ue_index","serving_cell","rank"]
    validateattributes(a.(name),{'numeric'},{'scalar','integer','positive','finite'});
end
validateattributes(a.mcs_index,{'numeric'},{'scalar','integer','nonnegative','finite'});
assert(a.rnti<=65519,'sixgr:calibration:AllocationRNTI','Use a valid unicast C-RNTI.');
if ischar(a.prb_set) || isstring(a.prb_set)
    assert(isscalar(string(a.prb_set)) && string(a.prb_set)==string(c.allocation_full_carrier_prbs), ...
        'sixgr:calibration:AllocationPRBs','Specify exact PRBs or all_carrier.');
    prbs=0:double(cfg.phy.carrier.NSizeGrid)-1;
else
    prbs=double(a.prb_set(:).');
end
symbols=double(a.symbol_allocation(:).');
slots=double(a.absolute_slots(:).'); rv=double(a.rv_sequence(:).');
validateattributes(prbs,{'numeric'},{'vector','integer','nonnegative','finite','nonempty'});
validateattributes(symbols,{'numeric'},{'vector','integer','nonnegative','finite','numel',2});
validateattributes(slots,{'numeric'},{'vector','integer','nonnegative','finite','nonempty'});
assert(numel(unique(prbs))==numel(prbs) && all(diff(slots)>0) && ...
    numel(rv)==numel(slots) && rv(1)==0 && all(ismember(rv,0:3)), ...
    'sixgr:calibration:AllocationHistory','Require unique PRBs, increasing slots and an explicit RV history starting at zero.');
policy=cfg.system.linkAbstraction.networkSpatial;
assert(string(sixgr.util.structGet(policy,'dlAntennaBasis','direct_ports'))=="direct_ports", ...
    'sixgr:calibration:AllocationAntennaBasis','Beam/element templates require their applied beam authority; this route uses direct ports.');
txPorts=policy.bsPorts; rxPorts=policy.uePorts;
if direction=="UL", txPorts=policy.uePorts; rxPorts=policy.bsPorts; end
assert(a.rank<=min(txPorts,rxPorts), ...
    'sixgr:calibration:AllocationRank','Rank exceeds configured transmit/receive dimensions.');
assert(isnumeric(a.precoder_real) && isnumeric(a.precoder_imag) && ...
    isreal(a.precoder_real) && isreal(a.precoder_imag) && ...
    isequal(size(a.precoder_real),[txPorts,a.rank]) && ...
    isequal(size(a.precoder_imag),[txPorts,a.rank]), ...
    'sixgr:calibration:AllocationPrecoder','Explicit real/imaginary matrices must be TX ports by layers.');
W=complex(double(a.precoder_real),double(a.precoder_imag));
assert(all(isfinite(W),'all') && abs(norm(W,'fro')^2-1)<1e-10 && rank(W)==a.rank, ...
    'sixgr:calibration:AllocationPrecoder','Precoder must have unit total power and full layer rank; no silent normalization.');
profile=sixgr.link.resolveMCSProfile(a.mcs_table,a.mcs_index);
assert(profile.Valid && ~startsWith(string(a.mcs_table),'experimental_'), ...
    'sixgr:calibration:AllocationMCS','Use a valid native NR MCS row; research transport needs its separate qualified recipe.');
assert(direction~="UL" || ~logical(cfg.phy.pusch.transformPrecoding), ...
    'sixgr:calibration:AllocationWaveform','DFT-s-OFDM requires a matching transform-domain calibration feature.');
frame=sixgr.phy.FrameStructureEngine(cfg,'FrameCoreOnly',true);
scheduler=sixgr.l2.mac.SchedulerRR(cfg,'Direction',direction);
grants=cell(1,numel(slots)); tbs=[];
for k=1:numel(slots)
    legal=frame.IsDLAllocation(slots(k),symbols);
    if direction=="UL", legal=frame.IsULAllocation(slots(k),symbols); end
    assert(legal,'sixgr:calibration:AllocationDuplex','Planned %s symbols are illegal at slot %d.',direction,slots(k));
    g=struct('Direction',char(direction),'Frame',floor(slots(k)/frame.SlotsPerFrame), ...
        'Slot',mod(slots(k),frame.SlotsPerFrame),'ScheduledAbsoluteSlot',slots(k), ...
        'RNTI',a.rnti,'UEIndex',a.ue_index,'ServingCell',a.serving_cell, ...
        'PRBSet',prbs,'SymbolAllocation',symbols,'Modulation',char(profile.Modulation), ...
        'TargetCodeRate',profile.TargetCodeRate,'MCSIndex',a.mcs_index,'MCSTable',char(a.mcs_table), ...
        'NumLayers',a.rank,'Layers',a.rank,'NumLogicalPorts',txPorts,'NumRFChains',txPorts, ...
        'RV',rv(k),'IsRetransmission',k>1,'TransportBlockIdentity',"unexecuted_calibration_template", ...
        'HARQTBContext',struct('OriginalNumLayers',a.rank), ...
        'PrecodingMatrixLogicalPorts',W,'PrecodingMatrix',W, ...
        'PrecoderNormalizationConvention','unit_frobenius', ...
        'PrecoderSource','configured_calibration_allocation_not_received_feedback', ...
        'ControlDeliveryModel','ideal_issued_grant', ...
        'AllocationSource','planned_calibration_allocation_not_executed_network_grant');
    if k>1, g.TBSBits=tbs; end
    g=scheduler.finalizeExactPHYFeasibility(g);
    assert(g.ExactPHYFeasible,'sixgr:calibration:AllocationInfeasible', ...
        'Exact scheduler allocation rejected: %s',g.ExactPHYInfeasibilityReason);
    if k==1, tbs=g.TBSBits; end
    assert(g.TBSBits==tbs && g.MCSIndex==a.mcs_index && g.NumLayers==a.rank, ...
        'sixgr:calibration:AllocationChanged','Calibration must preserve its declared coding/rank and original TB.');
    g.PHYGrant=sixgr.phy.grant.freezePHYGrant(cfg,direction,g,'Frame',g.Frame,'Slot',g.Slot);
    sixgr.system.abstraction.scheduledDataREMap(cfg,g,slots(k));
    grants{k}=g;
end
end
