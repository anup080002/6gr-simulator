function bindings=resolveReceivedAccessBindings(cfg,receipts,numUE)
% Resolve connected identities from one completed receiver record per UE.
% This does not qualify the bounded RRC codec or continuous network channels.
validateattributes(numUE,{'numeric'},{'scalar','integer','positive','finite'});
assert(iscell(receipts) && numel(receipts)==numUE, ...
    'sixgr:system:MissingUEAccessReceipt','Every UE needs its own received access result.');
rows=repmat(struct('UEIndex',NaN,'UEId',NaN,'ServingCell',NaN,'CellID',NaN, ...
    'RNTI',NaN,'CompletionSlot0',NaN,'BlockedSlotCount',NaN, ...
    'IdentitySource',"",'EncodingProfile',"",'Msg4PayloadSHA256',""),numUE,1);
for k=1:numUE
    receipt=receipts{k};
    assert(isstruct(receipt) && isscalar(receipt) && ...
        all(isfield(receipt,{'UEIndex','ServingCellIndex','Result'})), ...
        'sixgr:system:MissingUEAccessReceipt','Missing received access owner or result.');
    ue=double(receipt.UEIndex); cellIndex=double(receipt.ServingCellIndex);
    validateattributes(ue,{'numeric'},{'scalar','integer','>=',1,'<=',numUE});
    validateattributes(cellIndex,{'numeric'},{'scalar','integer','positive','finite'});
    r=receipt.Result;
    assert(isstruct(r) && isscalar(r) && ...
        all(isfield(r,{'DecodedMsg4','Msg4PDCCHCrcPass','Msg4PDSCHCrcPass', ...
        'Msg3ContentionIdentity','UEId','CellId'})), ...
        'sixgr:system:MissingUEAccessReceipt','Retain decoded Msg4 and its receiver ownership.');
    expectedUE=double(sixgr.util.structGet(cfg,'scenario.ue.startId',1))+ue-1;
    assert(isequal(double(r.UEId),expectedUE), ...
        'sixgr:system:UEAccessOwnerMismatch','A received result cannot be assigned to another UE.');
    assert(isfield(r.DecodedMsg4,'PayloadBytes'), ...
        'sixgr:system:MissingUEAccessReceipt','Retain received payload bytes, not only an identity label.');
    decoded=sixgr.mac.ra.parseMsg4ContentionResolution(r.DecodedMsg4.PayloadBytes);
    identity=sixgr.mac.ra.receivedMsg4Identity(decoded, ...
        r.Msg4PDCCHCrcPass,r.Msg4PDSCHCrcPass,string(r.Msg3ContentionIdentity));
    [slot0,blocked]=sixgr.truth.resolveRAAttachCompletion(r,cfg);
    rows(k)=struct('UEIndex',ue,'UEId',double(r.UEId),'ServingCell',cellIndex, ...
        'CellID',double(r.CellId),'RNTI',identity.RNTI,'CompletionSlot0',slot0, ...
        'BlockedSlotCount',blocked,'IdentitySource',identity.Source, ...
        'EncodingProfile',identity.EncodingProfile, ...
        'Msg4PayloadSHA256',string(sixgr.util.sha256Hex(uint8(r.DecodedMsg4.PayloadBytes))));
end
bindings=sortrows(struct2table(rows),'UEIndex');
assert(isequal(bindings.UEIndex,(1:numUE).'), ...
    'sixgr:system:DuplicateUEAccessReceipt','Missing or duplicate UE access owner.');
assert(height(unique(bindings(:,{'ServingCell','RNTI'})))==numUE, ...
    'sixgr:system:DuplicateReceivedCRNTI','Two connected UEs in one cell cannot share a received C-RNTI.');
end
