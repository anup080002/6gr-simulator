function evidence=captureGrantCalibrationEvidence(cfg,grant,tx,rx,state,options,rxInfo)
%CAPTUREGRANTCALIBRATIONEVIDENCE Retain the execution, not an asserted key.
% Path gains come from the SAME channel invocation as the decoded samples.
% No channel truth is supplied to Rx, and no calibration is accepted here.
assert(isfield(grant,'ScheduledAbsoluteSlot'), ...
    'sixgr:system:WaveformReplay:CalibrationGrantClock', ...
    'Grant-bound calibration requires the explicit scheduled absolute slot.');
[scheduled,carrier]=sixgr.system.abstraction.scheduledDataREMap( ...
    cfg,grant,double(grant.ScheduledAbsoluteSlot));
if string(grant.Direction)=="DL"
    native=tx.PDSCH; actualIndices=double(tx.PDSCHLayerIndices);
else
    native=tx.PUSCH; actualIndices=double(tx.PUSCHLayerIndices);
end
executed=sixgr.phy.resource.sharedDataREMap(tx.Carrier,native);
assert(tx.Carrier.NSlot==carrier.NSlot && tx.Carrier.NFrame==carrier.NFrame, ...
    'sixgr:system:WaveformReplay:CalibrationClockIdentity', ...
    'Executed frame/slot %g/%g differs from scheduled frame/slot %g/%g.', ...
    tx.Carrier.NFrame,tx.Carrier.NSlot,carrier.NFrame,carrier.NSlot);
assert(isequal(actualIndices,executed.LayerIndices1Based) && ...
    isequal(executed.NativeIndices1Based,scheduled.NativeIndices1Based) && ...
    isequal(executed.CodedBitsPerCodeword,scheduled.CodedBitsPerCodeword), ...
    'sixgr:system:WaveformReplay:CalibrationResourceIdentity', ...
    'Executed transmitter resources or clock differ from the frozen scheduled allocation.');
propagation=struct('UseFading',logical(state.UseFading), ...
    'ChannelSeed',state.ChannelSeed,'SampleRateHz',state.SampleRateHz, ...
    'ChannelInitialTime_s',state.ChannelInitialTime_s, ...
    'PathGains',state.PathGains,'PathFilters',state.PathFilters, ...
    'SampleTimes',state.ChannelSampleTimes, ...
    'ImplementationFilterTrimSamples',state.ChannelTrimSamples, ...
    'InputPadSamples',state.ChannelPadSamples,'Metadata',state.ChannelMetadata, ...
    'ReceiverOracleUsed',false);
if state.UseFading
    assert(~isempty(propagation.PathGains) && ~isempty(propagation.PathFilters) && ...
        ~isempty(propagation.SampleTimes) && ...
        size(propagation.PathGains,1)==numel(propagation.SampleTimes) && ...
        all(isfinite(propagation.PathGains),'all') && ...
        all(isfinite(propagation.PathFilters),'all') && ...
        all(isfinite(propagation.SampleTimes),'all'), ...
        'sixgr:system:WaveformReplay:CalibrationChannelEvidence', ...
        'The executed fading realization must retain finite native gains, filters and times.');
    propagation.Source="executed_waveform_channel_invocation_path_gains";
else
    propagation.Source="executed_identity_awgn_channel";
end
evidence=struct('Schema',"sixgr.grant_waveform_calibration_evidence/v1", ...
    'Grant',grant,'ResolvedConfig',cfg,'Transmitter',tx,'Receiver',rx, ...
    'ReceiverOFDMInfo',rxInfo.OFDM, ...
    'DataREMap',executed,'ScheduledDataREMap',scheduled, ...
    'Propagation',propagation,'Noise',state.NoiseProvenance, ...
    'AppliedImpairments',state.ImpairmentReplay,'ExecutionOptions',options, ...
    'SourceClassification',"executed_frozen_grant_waveform_diagnostic", ...
    'WaveformBacked',true,'CalibrationQualified',false,'PrimaryStudyAccepted',false);
end
