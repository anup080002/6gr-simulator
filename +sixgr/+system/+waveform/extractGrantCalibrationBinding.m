function [key,feature]=extractGrantCalibrationBinding(evidence)
%EXTRACTGRANTCALIBRATIONBINDING Offline runtime key from actual grant execution.
% This does not accept a caller-supplied profile string. Channel/receiver
% identities must have been retained by the native waveform execution path.
assert(all(isfield(evidence,{'CalibrationReceiverIdentity','CalibrationReceiverExecution'})) && ...
    evidence.CalibrationReceiverExecution.RecipeExecutionChecked && ...
    isfield(evidence.Propagation.Metadata,'CalibrationChannelIdentity'), ...
    'sixgr:calibration:GrantBindingEvidence','Missing executed native channel or receiver recipe binding.');
receiver=evidence.CalibrationReceiverIdentity;
assert(all(isfield(receiver,{'SINRPredictorModel','SpatialPredictor','PredictorPlane','ProfileID'})), ...
    'sixgr:calibration:GrantPredictorModel','Require the complete executed predictor recipe; do not infer a missing model.');
[feature,H]=sixgr.system.waveform.extractGrantCalibrationPredictor(evidence,receiver.SpatialPredictor, ...
    'Plane',receiver.PredictorPlane,'Model',receiver.SINRPredictorModel);
g=evidence.Grant; tx=evidence.Transmitter;
ctx=struct('Grant',g,'Direction',string(g.Direction),'TBSBits',double(tx.TransportBlockSize), ...
    'NumLayers',evidence.DataREMap.NumLayers,'TargetCodeRate',double(tx.TargetCodeRate), ...
    'SCS_kHz',double(tx.Carrier.SubcarrierSpacing), ...
    'ChannelModel',string(evidence.Propagation.Metadata.CalibrationChannelIdentity.NativeProperties.DelayProfile));
map=evidence.ScheduledDataREMap;
o=struct('Channel',reshape(H(1,1,:,:),size(H,3),size(H,4)), ...
    'RFProfileID',"ideal_rf_no_impairments", ...
    'ReceiverProfileID',receiver.ProfileID, ...
    'ChannelProfileID',evidence.Propagation.Metadata.CalibrationChannelIdentity.ProfileID, ...
    'ResourcePopulation',"native_shared_channel_data_re", ...
    'DataREAllocationIdentity',map.AllocationIdentity, ...
    'DataREAllocationSHA256',map.AllocationIdentitySHA256);
method=string(evidence.ResolvedConfig.system.linkAbstraction.effectiveSINRMethod);
key=sixgr.system.CalibratedLinkPHY.calibrationKey(ctx,o,receiver.SpatialPredictor,method);
feature.CalibrationKey=key;
feature.CalibrationKeySHA256=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(key),'UTF-8'))));
% Qualification is a separate statistical/domain/held-out gate.
feature.CalibrationQualified=false;
end
