function [independentSeeds,evolution]=validateGrantCalibrationSeeds(seeds,n)
%VALIDATEGRANTCALIBRATIONSEEDS Distinguish independent episodes from link time.
% Only a declared persistent link may reuse its CHANNEL seed within a TB.
% Noise, payload, control and RF streams remain independent. Returned seeds
% are the independent stream identities used for cross-episode/role checks.
assert(all(isfield(seeds,{'Bits','Noise','Channel','ControlNoise','RF'})) && ...
    isscalar(seeds.Bits) && numel(seeds.Noise)==n && numel(seeds.Channel)==n && ...
    numel(seeds.ControlNoise)==n && numel(seeds.RF)==n, ...
    'sixgr:calibration:GrantEpisodeSeeds','Seed dimensions must match planned attempts.');
evolution=string(sixgr.util.structGet(seeds,'ChannelEvolution','independent_attempt_realizations'));
assert(isscalar(evolution) && ismember(evolution, ...
    ["independent_attempt_realizations","persistent_link_absolute_slot"]), ...
    'sixgr:calibration:GrantEpisodeSeeds','Unknown channel-evolution policy.');
channel=double(seeds.Channel(:));
if evolution=="persistent_link_absolute_slot"
    assert(all(channel==channel(1)), 'sixgr:calibration:GrantEpisodeSeeds', ...
        'Persistent HARQ must retain one link-channel seed across all attempts.');
    channel=channel(1);
end
independentSeeds=double([seeds.Bits;seeds.Noise(:);channel;seeds.ControlNoise(:);seeds.RF(:)]);
assert(all(isfinite(independentSeeds)) && all(independentSeeds==fix(independentSeeds)) && ...
    all(independentSeeds>=0 & independentSeeds<=2^32-1) && ...
    numel(unique(independentSeeds))==numel(independentSeeds), ...
    'sixgr:calibration:GrantEpisodeSeeds', ...
    'Require distinct uint32-range streams, except the declared persistent channel trajectory.');
end
