function evidence=bindCalibrationReceiverIdentity(evidence,cfg)
%BINDCALIBRATIONRECEIVERIDENTITY Check actual decoder before binding a recipe.
% The input is the original baseline passed to replayGrant, not the mutated
% per-grant config. The capture already retains that resolved execution too.
assert(string(evidence.Schema)=="sixgr.grant_waveform_calibration_evidence/v1" && ...
    evidence.WaveformBacked,'sixgr:calibration:ReceiverEvidence','Require an executed waveform capture.');
direction=string(evidence.Grant.Direction);
type=string(cfg.system.linkAbstraction.receiverType);
identity=sixgr.system.abstraction.networkReceiverCalibrationIdentity(cfg,direction,type);
o=evidence.ExecutionOptions; rx=evidence.Receiver;
assert(~o.FastAWGNPath && o.LDPCMaxIterations==0 && ~o.UseGPU, ...
    'sixgr:calibration:ReceiverRecipeOptions', ...
    'Fast paths, GPU or explicit decoder caps need a separate matching receiver recipe.');
assert(isfield(rx,'MaxDecoderIterations') && rx.MaxDecoderIterations==identity.MaxIterations && ...
    string(sixgr.util.structGet(rx,'MeasuredLDPCDecoderAlgorithm',''))==identity.LDPCAlgorithm, ...
    'sixgr:calibration:ReceiverRecipeDecoder','Actual LDPC settings differ from the calibration recipe.');
expected="MMSE"; if type=="zf", expected="ZF"; end
assert(strcmpi(string(sixgr.util.structGet(rx,'EqualizerType','')),expected), ...
    'sixgr:calibration:ReceiverRecipeEqualizer','Actual equalizer differs from the spatial predictor.');
source=string(sixgr.util.structGet(rx,'ChannelEstimateSource',''));
assert(any(source==["pdsch_dmrs_channel_estimate","pusch_dmrs_channel_estimate"]), ...
    'sixgr:calibration:ReceiverRecipeEstimator','Require the actually executed pilot estimator, not oracle H.');
evidence.CalibrationReceiverIdentity=identity;
evidence.CalibrationReceiverExecution=struct('EqualizerType',string(rx.EqualizerType), ...
    'MaxIterations',rx.MaxDecoderIterations,'LDPCAlgorithm',identity.LDPCAlgorithm, ...
    'ChannelEstimateSource',source,'RecipeExecutionChecked',true);
end
