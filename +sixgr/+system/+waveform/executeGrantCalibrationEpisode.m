function episode=executeGrantCalibrationEpisode(cfg,grants,snrHistory,seeds)
%EXECUTEGRANTCALIBRATIONEPISODE Decode one original TB through issued grants.
% The caller supplies frozen grants (including each attempt's actual clock),
% not a rectangle or a caller-asserted calibration key. This collector is
% raw waveform evidence, not an accepted BLER curve or SLS calibration.
arguments
    cfg (1,1) struct
    grants (1,:) cell
    snrHistory (1,:) double {mustBeFinite}
    seeds (1,1) struct
end
n=numel(grants);
assert(n>=1 && numel(snrHistory)==n && ...
    all(isfield(seeds,{'Bits','Noise','Channel','ControlNoise','RF'})), ...
    'sixgr:calibration:GrantEpisodePlan', ...
    'Supply one SNR and explicit noise/channel/control seeds for each issued grant.');
assert(isscalar(seeds.Bits) && numel(seeds.Noise)==n && ...
    numel(seeds.Channel)==n && numel(seeds.ControlNoise)==n && numel(seeds.RF)==n, ...
    'sixgr:calibration:GrantEpisodeSeeds','Seed plan dimensions differ from the attempt plan.');
[~,evolution]=sixgr.system.waveform.validateGrantCalibrationSeeds(seeds,n);

maps=cell(n,1); slots=zeros(n,1); rv=zeros(n,1);
first=grants{1};
assert(isstruct(first) && isscalar(first) && ...
    all(isfield(first,{'Direction','TBSBits','TransportBlockIdentity','RNTI','NumLayers'})), ...
    'sixgr:calibration:GrantEpisodeIdentity','Require explicit grant, original-TB identity and TBS.');
direction=string(first.Direction); tbs=double(first.TBSBits);
identity=string(first.TransportBlockIdentity);
assert(isscalar(identity) && strlength(strtrim(identity))>0 && ...
    isscalar(tbs) && isfinite(tbs) && tbs>=24 && tbs==fix(tbs) && ...
    any(direction==["DL","UL"]), ...
    'sixgr:calibration:GrantEpisodeIdentity','Invalid original-TB identity, direction or exact TBS.');
% Validate the complete plan before executing any attempt. Skipped retries
% must not conceal malformed frozen contexts in an apparently good episode.
for k=1:n
    g=grants{k};
    assert(isstruct(g) && isscalar(g) && ...
        all(isfield(g,{'TBSBits','TransportBlockIdentity','RV','ScheduledAbsoluteSlot','IsRetransmission'})), ...
        'sixgr:calibration:GrantEpisodeIdentity','Every planned attempt needs explicit TB and retry identity.');
    slots(k)=double(g.ScheduledAbsoluteSlot); rv(k)=double(g.RV);
    maps{k}=sixgr.system.abstraction.scheduledDataREMap(cfg,g,slots(k));
    assert(string(g.Direction)==direction && string(g.TransportBlockIdentity)==identity && ...
        g.RNTI==first.RNTI && g.TBSBits==tbs && ...
        g.PHYGrant.CodingLayout.TBSBits==tbs && ...
        g.NumLayers==first.NumLayers && ...
        rv(k)==g.PHYGrant.HARQProcessKey.RV && ismember(rv(k),0:3) && ...
        isequal(logical(g.IsRetransmission),k>1) && ...
        isequal(logical(g.PHYGrant.HARQProcessKey.IsRetransmission),k>1), ...
        'sixgr:calibration:GrantEpisodeIdentity', ...
        'A HARQ episode must preserve its UE, TB, layers and frozen RV/retry authority.');
end
assert(rv(1)==0 && all(diff(slots)>0), ...
    'sixgr:calibration:GrantEpisodeClock','Initial RV must be zero and retry clocks strictly increasing.');

key=char(direction+"|tb="+identity+"|tbs="+string(tbs));
[occupied,~]=sixgr.system.waveform.harqSoftBufferCache('get',key);
assert(~occupied,'sixgr:calibration:GrantEpisodeCacheOwnership', ...
    'This original-TB identity already owns a live HARQ buffer; do not overwrite it.');
release=onCleanup(@()sixgr.system.waveform.harqSoftBufferCache('clear',key)); %#ok<NASGU>
priorRNG=rng;
restoreRNG=onCleanup(@()rng(priorRNG)); %#ok<NASGU>
bitsStream=RandStream('mt19937ar','Seed',double(seeds.Bits));
payload=int8(randi(bitsStream,[0 1],tbs,1));
payloadHash=string(sixgr.util.sha256Hex(uint8(payload)));
records=struct([]); captures=cell(0,1); replays=cell(0,1);
bindings=cell(0,1); features=cell(0,1);
for k=1:n
    % AWGN and fading have their explicit streams. Isolate any RF branch
    % using the global stream too, and restore the caller's RNG on error.
    rng(double(seeds.RF(k)),'twister');
    initialTime=0;
    if evolution=="persistent_link_absolute_slot"
        initialTime=sixgr.system.waveform.resolveReplayChannelTime( ...
            cfg,grants{k},'ScheduledAbsoluteSlot',[]);
    end
    [r,c]=sixgr.system.waveform.replayGrant(cfg,direction,grants{k},payload,snrHistory(k), ...
        'StrictMode',true,'CompactPHYIO',false,'FastAWGNPath',false,'AdaptiveLDPC',false, ...
        'NoiseSeed',seeds.Noise(k),'ChannelSeed',seeds.Channel(k), ...
        'ChannelInitialTime_s',initialTime, ...
        'ControlNoiseSeed',seeds.ControlNoise(k));
    assert(r.WaveformReplayExecuted && ismember(r.CRCError,[0 1]) && ...
        ~isempty(fieldnames(c)), ...
        'sixgr:calibration:GrantEpisodeExecution', ...
        'No data waveform/CRC evidence exists; do not count a control rejection as a data BLER trial.');
    assert(r.TransmittedTransportBlockSHA256==payloadHash && ...
        r.TransmittedTransportBlockBits==tbs && r.TransmittedRV==rv(k) && ...
        isequal(int8(c.Transmitter.TransportBlock(:)),payload) && ...
        c.ScheduledDataREMap.AllocationIdentitySHA256==maps{k}.AllocationIdentitySHA256, ...
        'sixgr:calibration:GrantEpisodeTB','Executed TB or allocation differs from the original issued plan.');
    assert(k==1 || (r.HARQSoftBufferPriorAvailable && r.HARQSoftCombiningApplied), ...
        'sixgr:calibration:GrantEpisodeCombining','A retry discarded the original decoder soft buffer.');
    assert(r.AWGNNoiseSeedApplied && r.AWGNNoiseSeed==seeds.Noise(k) && ...
        r.ReplayChannelSeed==seeds.Channel(k) && r.ReplayChannelInitialTime_s==initialTime && ...
        c.Propagation.ChannelInitialTime_s==initialTime, ...
        'sixgr:calibration:GrantEpisodeSeeds','Executed noise/channel seeds differ from the episode plan.');
    assert(r.CRCError || (r.BitErrors==0 && r.BitsCompared==tbs), ...
        'sixgr:calibration:GrantEpisodeScoring','CRC success disagrees with independent original-TB scoring.');
    binding=struct(); feature=struct(); bindingSHA="";
    if isfield(c,'CalibrationReceiverIdentity')
        [binding,feature]=sixgr.system.waveform.extractGrantCalibrationBinding(c);
        bindingSHA=feature.CalibrationKeySHA256;
        assert(k==1 || isequaln(bindings{1},binding), ...
            'sixgr:calibration:GrantEpisodeRuntimeKey', ...
            'This SLS HARQ curve requires an unchanged coding/resource/receiver key across retries.');
    end
    rec=struct('Attempt',k,'RV',rv(k),'ScheduledAbsoluteSlot0',slots(k), ...
        'ConfiguredSNRdB',snrHistory(k),'CRCError',logical(r.CRCError), ...
        'TBSBits',tbs,'TransportBlockSHA256',payloadHash, ...
        'PriorAttemptsFailed',k>1,'HARQSoftCombiningApplied',logical(r.HARQSoftCombiningApplied), ...
        'BitsSeed',double(seeds.Bits),'NoiseSeed',double(seeds.Noise(k)), ...
        'ChannelSeed',double(seeds.Channel(k)),'ControlNoiseSeed',double(seeds.ControlNoise(k)), ...
        'ChannelInitialTime_s',initialTime, ...
        'RFGlobalStreamSeed',double(seeds.RF(k)), ...
        'DataREAllocationSHA256',maps{k}.AllocationIdentitySHA256, ...
        'CalibrationKeySHA256',bindingSHA,'CalibrationBindingAvailable',strlength(bindingSHA)>0, ...
        'WaveformExecuted',true);
    if isempty(records), records=rec; else, records(end+1)=rec; end %#ok<AGROW>
    captures{end+1,1}=c; replays{end+1,1}=r; %#ok<AGROW>
    bindings{end+1,1}=binding; features{end+1,1}=feature; %#ok<AGROW>
    if ~r.CRCError, break; end
end
episode=struct('Schema',"sixgr.frozen_grant_calibration_episode/v1", ...
    'Attempts',records,'Captures',{captures},'Replays',{replays}, ...
    'CalibrationBindings',{bindings},'SpatialPredictorFeatures',{features}, ...
    'PlannedGrants',{grants},'PlannedSNRdB',snrHistory,'SeedPlan',seeds, ...
    'OriginalTransportBlock',payload,'ResolvedConfig',cfg, ...
    'Delivered',~records(end).CRCError,'StopReason',"attempt_budget_exhausted", ...
    'ChannelEvolution',evolution, ...
    'ControlDeliveryModel',"ideal_issued_grant_unless_physical_binding_required", ...
    'SourceClassification',"executed_frozen_grant_waveform_episode", ...
    'WaveformBacked',true,'CalibrationQualified',false,'PrimaryStudyAccepted',false);
if episode.Delivered, episode.StopReason="crc_success"; end
end
