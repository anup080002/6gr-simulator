function validateSLSPUSCHUCIReservation(obligation,context)
%VALIDATESLSPUSCHUCIRESERVATION A transport label cannot release PUCCH REs.
% Require the actual issued PUSCH and its explicitly bound UCI allocation.
% This validates resource ownership only, not received DCI or decoded UCI.
required={'PUSCHGrant','PUSCHGrantSHA256','PUSCHUCIAllocatedRECount','RNTI'};
assert(all(isfield(obligation,required)), ...
    'sixgr:system:MissingPUSCHUCIReservationBinding', ...
    'PUSCH transport must retain the frozen issued grant, digest and allocated UCI RE count.');
g=obligation.PUSCHGrant;
fields={'RNTI','UEIndex','ControlAbsoluteSlot','ScheduledAbsoluteSlot','PRBSet','SymbolAllocation'};
assert(isstruct(g) && isscalar(g) && all(isfield(g,fields)), ...
    'sixgr:system:PUSCHUCIReservationBinding','The selected UCI transport needs an exact issued PUSCH grant.');
digest=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(sixgr.util.jsonSafeValue(g)),'UTF-8'))));
assert(isscalar(string(obligation.PUSCHGrantSHA256)) && digest==string(obligation.PUSCHGrantSHA256), ...
    'sixgr:system:PUSCHUCIReservationBinding','The bound PUSCH was changed after UCI transport selection.');
assert(g.RNTI==obligation.RNTI && g.UEIndex==obligation.UEIndex && ...
    g.ScheduledAbsoluteSlot==obligation.AbsoluteSlot0 && ...
    isfinite(g.ControlAbsoluteSlot) && g.ControlAbsoluteSlot>=0 && ...
    g.ControlAbsoluteSlot<=obligation.KnownAtAbsoluteSlot0 && ...
    g.ControlAbsoluteSlot<=context.AsOfAbsoluteSlot0, ...
    'sixgr:system:PUSCHUCIReservationBinding','UCI transport must match the UE and causal control/data clock.');
assert(isfield(g,'ServingCell') && g.ServingCell==obligation.CellID, ...
    'sixgr:system:PUSCHUCIReservationBinding','UCI transport belongs to a different serving cell.');
issued=sixgr.util.structGet(context,'IssuedPUSCHGrants',struct([]));
matched=false;
for k=1:numel(issued)
    if iscell(issued), candidate=issued{k}; else, candidate=issued(k); end
    issuedDigest=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(sixgr.util.jsonSafeValue(candidate)),'UTF-8'))));
    matched=matched || issuedDigest==digest;
end
assert(matched,'sixgr:system:PUSCHUCIReservationBinding', ...
    'The transport binding must occur in the runtime issued-grant population.');
count=double(obligation.PUSCHUCIAllocatedRECount);
assert(isscalar(count) && isfinite(count) && count==fix(count) && count>0 && ...
    isfield(g,'SLSUCIAllocation') && isstruct(g.SLSUCIAllocation) && ...
    isscalar(g.SLSUCIAllocation) && isfield(g.SLSUCIAllocation,'AllocatedRECount') && ...
    isequal(double(g.SLSUCIAllocation.AllocatedRECount),count), ...
    'sixgr:system:MissingPUSCHUCIReservationBinding', ...
    'UCI must consume explicitly allocated PUSCH REs; a transport string is insufficient.');
assert(isfield(g.SLSUCIAllocation,'Coordinates0Based'), ...
    'sixgr:system:MissingPUSCHUCIReservationBinding','Retain exact carrier-relative UCI RE coordinates.');
coordinates=double(g.SLSUCIAllocation.Coordinates0Based);
a=double(g.SymbolAllocation(:).');
assert(size(coordinates,2)==2 && size(coordinates,1)==count && ...
    size(unique(coordinates,'rows'),1)==count && all(isfinite(coordinates),'all') && ...
    all(coordinates>=0 & coordinates==fix(coordinates),'all') && numel(a)==2 && ...
    all(ismember(floor(coordinates(:,1)/12),double(g.PRBSet))) && ...
    all(coordinates(:,2)>=a(1) & coordinates(:,2)<sum(a)), ...
    'sixgr:system:PUSCHUCIReservationBinding','UCI REs must be unique and inside the frozen PUSCH allocation.');
plan=g.SLSUCIAllocation;
if all(isfield(obligation,{'HARQBits','CSIPart1Bits','CSIPart2Bits'}))
    assert(isfield(plan,'LengthsHARQCSI1CSI2') && ...
        isequal(double(plan.LengthsHARQCSI1CSI2), ...
        double([obligation.HARQBits obligation.CSIPart1Bits obligation.CSIPart2Bits])), ...
        'sixgr:system:PUSCHUCIReservationBinding', ...
        'The frozen native UCI lengths must match the scheduled obligation; SR is not a PUSCH payload bit.');
end
assert(isfield(plan,'Schema') && string(plan.Schema)=="sixgr.native_pusch_uci_resources/v1" && ...
    isfield(plan,'SHA256') && string(plan.SHA256)==string(sixgr.util.sha256Hex( ...
    uint8(unicode2native(jsonencode(rmfield(plan,'SHA256')),'UTF-8')))) && ...
    isequal(plan.PRBSet,double(g.PRBSet(:).')) && isequal(plan.SymbolAllocation,a), ...
    'sixgr:system:PUSCHUCIReservationBinding', ...
    'A manually supplied RE count cannot release PUCCH: retain the native multiplex plan for this PUSCH.');
pucch=double(obligation.Coordinates0Based);
assert(~isempty(pucch) && size(pucch,2)==3 && all(isfinite(pucch),'all') && ...
    all(pucch>=0 & pucch==fix(pucch),'all') && ...
    any(pucch(:,2)>=a(1) & pucch(:,2)<sum(a)), ...
    'sixgr:system:PUSCHUCIReservationBinding', ...
    'A nonoverlapping or missing PUCCH occasion cannot be released by selecting PUSCH.');
end
