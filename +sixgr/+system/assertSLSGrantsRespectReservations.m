function assertSLSGrantsRespectReservations(grants,reservation)
%ASSERTSLSGRANTSRESPECTRESERVATIONS Reject collisions before freezing grants.
mask=reservation.SchedulerAvailablePRBSymbolMask;
for k=1:numel(grants)
    g=grants(k);
    assert(all(isfield(g,{'PRBSet','SymbolAllocation'})), ...
        'sixgr:system:ReservationGrantSchema','Grants require exact PRBSet and SymbolAllocation.');
    p=double(g.PRBSet(:)); a=double(g.SymbolAllocation(:).');
    assert(~isempty(p) && numel(unique(p))==numel(p) && numel(a)==2 && ...
        all(isfinite([p;a(:)])) && all([p;a(:)]==fix([p;a(:)])) && ...
        all(p>=0 & p<size(mask,1)) && a(1)>=0 && a(2)>0 && sum(a)<=size(mask,2), ...
        'sixgr:system:ReservationGrantBounds','Scheduled grant lies outside the opportunity grid.');
    assert(all(mask(p+1,a(1)+(1:a(2))),'all'), ...
        'sixgr:system:ReservedResourceCollision', ...
        'Data grant collides with configured or causally scheduled resources at cell %d slot0 %d.', ...
        reservation.CellID,reservation.DataAbsoluteSlot0);
end
end
