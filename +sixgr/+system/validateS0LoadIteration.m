function identity = validateS0LoadIteration(result, expected)
%VALIDATES0LOADITERATION Qualify one executed S0 FTP3 load observation.
% This validates evidence identity, not convergence to a requested load.
% A calibrated-link result remains an SLS estimate, never waveform truth.
arguments
    result struct
    expected struct
end
requiredExpected = {'ArrivalRatePerCell_s','SeedBundle','PlannedExecutionArchitecture'};
if ~isscalar(expected) || ~all(isfield(expected,requiredExpected))
    error('sixgr:system:S0LoadExpectation', ...
        'Expected rate, seed bundle and explicit execution architecture are required.');
end
architecture=string(expected.PlannedExecutionArchitecture);
if ~isscalar(architecture) || ~ismember(architecture,["waveform","calibrated_link_abstraction"])
    error('sixgr:system:S0LoadExpectation', ...
        'PlannedExecutionArchitecture must be waveform or calibrated_link_abstraction.');
end
if ~isscalar(result) || ~isfield(result,'Ok') || ~isequal(result.Ok,true) || ...
        ~isfield(result,'Details') || ~isstruct(result.Details) || ~isscalar(result.Details)
    error('sixgr:system:S0LoadRunFailed','The S0 runtime did not complete successfully.');
end
d=result.Details;
required={'WaveformBacked','ProxyPHYActive','FallbackUsed','SeedBundle', ...
    'SchedulerGrants','ResourceOpportunityTable','TrafficArrivalEvents', ...
    'TrafficModel','TrafficArrivalRatePerCell_s','TrafficArrivalStreamID', ...
    'TrafficDefinitionSource','TrafficDeterministic', ...
    'LoadCalibrationBaseConfigSHA256','DecodeUnavailableUL'};
if ~all(isfield(d,required)) || ~istable(sixgr.util.structGet(d,'SchedulerGrants',[])) || ...
        ~istable(sixgr.util.structGet(d,'ResourceOpportunityTable',[])) || ...
        ~istable(sixgr.util.structGet(d,'TrafficArrivalEvents',[]))
    error('sixgr:system:S0LoadEvidence', ...
        'S0 requires exact executed grants, independent opportunities and retained FTP3 arrivals.');
end
grants=d.SchedulerGrants;
opportunities=d.ResourceOpportunityTable;
arrivals=d.TrafficArrivalEvents;
grantColumns=["TTI","CellID","Direction","PRBSet","SymbolStart","NumSymbols", ...
    "TBSBits","PHYDecisionRole","PHYDecisionStatus","WaveformReplayExecuted", ...
    "CalibrationQualified","CalibrationSHA256","CalibrationKeySHA256", ...
    "SourceClassification"];
opportunityColumns=["TTI","CellID","Direction","PRBSet","SymbolStart", ...
    "NumSymbols","Source"];
arrivalColumns=["ArrivalID","ArrivalTTI","ArrivalTime_s","UEID", ...
    "FileSizeBytes","OfferedBits","Direction","Seed", ...
    "ArrivalStreamID","ArrivalProcess"];
if isempty(opportunities) || ...
        ~all(ismember(grantColumns,string(grants.Properties.VariableNames))) || ...
        ~all(ismember(opportunityColumns,string(opportunities.Properties.VariableNames))) || ...
        ~all(ismember(arrivalColumns,string(arrivals.Properties.VariableNames))) || ...
        strlength(string(d.TrafficArrivalStreamID))==0 || ...
        string(d.TrafficDefinitionSource)~= ...
            "configured_fixed_file_continuous_time_poisson_ftp3" || ...
        ~isequal(d.TrafficDeterministic,true) || ...
        any(string(arrivals.ArrivalStreamID)~=string(d.TrafficArrivalStreamID)) || ...
        any(string(arrivals.ArrivalProcess)~="fixed_file_continuous_time_poisson") || ...
        (isempty(grants) ~= isempty(arrivals)) || ...
        any(~isfinite(double(grants.TBSBits))) || any(double(grants.TBSBits)<=0) || ...
        any(~ismember(string(grants.Direction),["DL","UL"])) || ...
        any(string(opportunities.Source)~="executed_slot_scheduler_budget_independent_of_grants")
    error('sixgr:system:S0LoadEvidence', ...
        'S0 requires executed-grant schema, independent opportunities and a causal FTP3 arrival ledger.');
end
waveform=isequal(d.WaveformBacked,true) && isequal(d.ProxyPHYActive,false);
abstract=string(sixgr.util.structGet(d,'ExecutionBackend',''))=="CALIBRATED_LINK_ABSTRACTION" && ...
    isequal(d.WaveformBacked,false) && isequal(d.ProxyPHYActive,true) && ...
    isequal(sixgr.util.structGet(d,'CalibrationQualified',false),true) && ...
    string(sixgr.util.structGet(d,'SourceClassification',''))== ...
        "calibrated_sls_estimate_not_waveform_truth" && ...
    strlength(string(sixgr.util.structGet(d,'CalibrationSHA256','')))==64;
if waveform && (any(string(grants.PHYDecisionRole)~="measured") || ...
        any(string(grants.PHYDecisionStatus)~="OK") || ...
        any(~logical(grants.WaveformReplayExecuted)) || ...
        any(string(grants.SourceClassification)=="calibrated_sls_estimate_not_waveform_truth"))
    error('sixgr:system:S0LoadEvidence', ...
        'Waveform S0 calibration requires executed measured PHY evidence for every grant.');
end
if abstract && (any(string(grants.PHYDecisionRole)~="calibrated_sls_estimate") || ...
        any(string(grants.PHYDecisionStatus)~="OK") || ...
        any(logical(grants.WaveformReplayExecuted)) || ...
        any(~logical(grants.CalibrationQualified)) || ...
        any(string(grants.CalibrationSHA256)~=string(d.CalibrationSHA256)) || ...
        any(strlength(string(grants.CalibrationKeySHA256))~=64) || ...
        any(string(grants.SourceClassification)~="calibrated_sls_estimate_not_waveform_truth"))
    error('sixgr:system:S0LoadEvidence', ...
        'Abstract S0 calibration requires qualified in-package decisions for every grant.');
end
if architecture=="waveform", acceptedBackend=waveform; else, acceptedBackend=abstract; end
decodeUnavailable=double(d.DecodeUnavailableUL);
rate=double(expected.ArrivalRatePerCell_s);
if ~acceptedBackend || ~isequal(d.FallbackUsed,false) || ...
        ~isscalar(rate) || ~isfinite(rate) || rate<=0 || ...
        ~isequal(lower(string(d.TrafficModel)),"ftp3") || ...
        ~isequal(double(d.TrafficArrivalRatePerCell_s),rate) || ...
        strlength(string(d.LoadCalibrationBaseConfigSHA256))~=64 || ...
        any(~isfinite(decodeUnavailable),'all') || any(decodeUnavailable~=0,'all') || ...
        ~isequaln(d.SeedBundle,expected.SeedBundle)
    error('sixgr:system:S0LoadEvidence', ...
        ['S0 load calibration requires the planned qualified backend, frozen seeds, ' ...
         'FTP3 arrivals, unchanged base configuration and no unavailable UL decode.']);
end
identity=struct('PHYExecutionMode',"waveform",'CalibrationSHA256',"", ...
    'BaseConfigSHA256',string(d.LoadCalibrationBaseConfigSHA256), ...
    'ArrivalRatePerCell_s',rate);
if abstract
    identity.PHYExecutionMode="CALIBRATED_LINK_ABSTRACTION";
    identity.CalibrationSHA256=string(d.CalibrationSHA256);
end
end
