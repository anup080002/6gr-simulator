function emissions=buildScheduledSSBEmissions(cfg,state)
% Native PSS/SSS/coded PBCH/DM-RS on the configured absolute burst clock.
% Source stage only: a reservation is not a transmitted grid, and generated
% symbols are not evidence of reception, acquisition or qualified SLS BLER.
emissions=struct([]);
p=cfg.system.linkAbstraction.networkSpatial;
assert(string(p.ssbPowerPolicy)=="configured_bs_full_carrier_psd_with_ssb_offsets" && ...
    string(p.ssbPhaseAssumption)=="native_sequence_phase_at_committed_epoch" && ...
    string(p.ssbBeamPolicy)=="configured_ssb_physical_precoders", ...
    'sixgr:abstraction:SSBEmissionPolicy','Declare SSB power, phase and physical beam policy.');
assert(isnumeric(state.TTI) && isscalar(state.TTI) && isfinite(state.TTI) && ...
    state.TTI>=1 && state.TTI==fix(state.TTI) && ...
    isnumeric(state.AbsoluteSlot0) && isscalar(state.AbsoluteSlot0) && ...
    isreal(state.AbsoluteSlot0) && state.AbsoluteSlot0==state.TTI-1, ...
    'sixgr:abstraction:SSBEmissionClock','SSB source must use AbsoluteSlot0=TTI-1.');
if ~logical(sixgr.util.structGet(cfg,'phy.ssb.enable',false)), return; end
assert(logical(sixgr.util.structGet(cfg,'phy.pbch.enable',false)), ...
    'sixgr:abstraction:SSBEmissionPBCH','Enabled SS/PBCH emission requires PBCH, not a dummy reservation.');
carrier=sixgr.phy.grid.makeCarrier(cfg); slot=state.AbsoluteSlot0;
assert(strcmpi(carrier.CyclicPrefix,'normal'), ...
    'sixgr:abstraction:SSBEmissionGrid','Native SS/PBCH mapping requires normal CP.');
timing=sixgr.phy.frame.SSBTimingResolver.resolveFromConfig(cfg);
assert(timing.SSBSubcarrierSpacingKHz==carrier.SubcarrierSpacing && ...
    any(carrier.SubcarrierSpacing==[15 30 60 120]), ...
    'sixgr:abstraction:SSBEmissionGrid', ...
    'Mixed-numerology or extended-SCS SSB needs an explicit sample-domain source; never round it onto this grid.');
plan=sixgr.phy.ia.SSBBurstPlan.fromConfig(cfg,timing);
assert(plan.NumTransmitAntennas==p.bsPorts, ...
    'sixgr:abstraction:SSBEmissionBeam','Configured physical SSB precoders must match the BS channel dimensions.');
slotsPerHalf=carrier.SlotsPerFrame/2; half=floor(slot/slotsPerHalf);
origin=timing.HalfFrameIndex; period=timing.PeriodicityMs/5;
if half<origin || mod(half-origin,period)~=0, return; end
relativeSlot=mod(slot,slotsPerHalf);
sfn=mod(floor(slot/carrier.SlotsPerFrame),1024); halfBit=mod(half,2);
g=timing.GridRelationship;
placement=sixgr.phy.ia.SSBGridValidator.validate( ...
    'CarrierSubcarrierSpacingKHz',carrier.SubcarrierSpacing, ...
    'SSBSubcarrierSpacingKHz',timing.SSBSubcarrierSpacingKHz, ...
    'NStartGrid',carrier.NStartGrid,'NSizeGrid',carrier.NSizeGrid, ...
    'NStartBWP',carrier.NStartGrid,'NSizeBWP',carrier.NSizeGrid, ...
    'NCRBSSB',g.NCRBSSB,'KSSB',g.KSSB);
firstSC=(placement.SSBLowOffsetFromPointAHz-placement.CarrierLowOffsetFromPointAHz)/ ...
    (1000*carrier.SubcarrierSpacing);
assert(firstSC==fix(firstSC), 'sixgr:abstraction:SSBEmissionGrid', ...
    'Fractional subcarrier placement requires sample-domain frequency translation, not rounding.');
power=double(state.LargeScaleState.TxPower_dBm); nc=size(power,2);
assert(~isempty(power) && isreal(power) && all(isfinite(power),'all') && ...
    all(abs(power-power(1,:))<1e-12,'all'), ...
    'sixgr:abstraction:SSBEmissionPower','Require a common finite BS power per cell.');
ids=double(p.ssbCellIDs(:));
assert(numel(ids)==nc && isreal(ids) && all(isfinite(ids) & ids>=0 & ids<=1007 & ids==fix(ids)), ...
    'sixgr:abstraction:SSBEmissionIdentity','Supply one physical cell ID (0..1007) per transmitting cell.');
m=cfg.phy.mib;
assert(all(isfield(m,{'pdcchConfigSIB1','dmrsTypeAPosition','cellBarred','intraFreqReselection'})), ...
    'sixgr:abstraction:SSBEmissionMIB','Require installed MIB fields; never synthesize random or all-zero payloads.');
validateattributes(m.cellBarred,{'numeric','logical'},{'scalar','real','finite','binary'});
validateattributes(m.intraFreqReselection,{'numeric','logical'},{'scalar','real','finite','binary'});
spacing="scs15or60"; if any(carrier.SubcarrierSpacing==[30 120]), spacing="scs30or120"; end
% Preserve the installed SSB_Tx/nrWaveformGenerator wire-bit convention:
% CellBarred=1 encodes notBarred (the ASN.1 enumerator), despite the name.
barred="barred"; if m.cellBarred, barred="notBarred"; end
reselection="allowed"; if m.intraFreqReselection, reselection="notAllowed"; end
mib=sixgr.phy.ia.MIBSemanticValidator.resolve( ...
    'SystemFrameNumberMSB6',floor(sfn/16),'SubCarrierSpacingCommon',spacing, ...
    'SSBSubcarrierOffset',mod(g.KSSB,16),'DMRSTypeAPosition',"pos"+string(m.dmrsTypeAPosition), ...
    'PDCCHConfigSIB1',m.pdcchConfigSIB1,'CellBarred',barred, ...
    'IntraFreqReselection',reselection,'Spare',0);
bits=int8([0;mib.InformationBits]); % BCCH-BCH message CHOICE followed by MIB.
part=sixgr.util.resolveTDDSlotPartition(cfg,slot); dl=part.DLSymbolAllocation;
for c=1:nc
    pci=ids(c);
    for index=reshape(plan.ActiveSSBIndices0Based,1,[])
        absoluteSymbols=plan.CandidateSymbols0Based(index+1)+(0:3);
        selected=find(floor(absoluteSymbols/carrier.SymbolsPerSlot)==relativeSlot);
        if isempty(selected), continue; end
        localSymbols=mod(absoluteSymbols(selected),carrier.SymbolsPerSlot);
        assert(all(localSymbols>=dl(1) & localSymbols<sum(dl)), ...
            'sixgr:abstraction:SSBEmissionTiming','Transmitted SSB symbols must be DL in the configured TDD clock.');
        indexOffset=g.KSSB; if timing.Lmax==64, indexOffset=index; end
        cw=nrBCH(bits,sfn,halfBit,timing.Lmax,indexOffset,pci);
        ibar=mod(index,8); if timing.Lmax==4, ibar=index+4*halfBit; end
        grid=complex(zeros(240,4));
        grid(nrPSSIndices)=nrPSS(mod(pci,3));
        grid(nrSSSIndices)=nrSSS(pci);
        grid(nrPBCHIndices(pci))=nrPBCH(cw,pci,mod(index,8));
        grid(nrPBCHDMRSIndices(pci))=nrPBCHDMRS(pci,ibar);
        slice=grid(:,selected); occupied=find(slice~=0);
        [sc,symbol]=ind2sub(size(slice),occupied);
        coords=[firstSC+sc-1,reshape(localSymbols(symbol),[],1)];
        [reservedSC,reservedSymbol]=ndgrid(firstSC+(0:239),localSymbols);
        reserved=[reservedSC(:),reservedSymbol(:)];
        values=double(slice(occupied)); W=reshape(plan.PrecoderMatrices{index+1},[],1);
        assert(all(isfinite(W)) && abs(sum(abs(W).^2)-1)<1e-12 && ...
            all(abs(abs(values).^2-1)<1e-12), ...
            'sixgr:abstraction:SSBEmissionPower','Require native unit-EPRE symbols and a unit-norm physical beam.');
        watts=10^((power(1,c)-30)/10);
        epre=watts/(12*carrier.NSizeGrid)*10^(plan.PerSSBPowerDB(index+1)/10);
        row=struct('SourceTTI',state.TTI,'AbsoluteSlot0',slot,'ServingCellID',c, ...
            'NCellID',pci,'SSBIndex0',index,'SystemFrameNumber',sfn,'HalfFrameBit',halfBit, ...
            'Signal',"SSB_PSS_SSS_PBCH_DMRS",'Coordinates0Based',coords, ...
            'ReservedCoordinates0Based',reserved, ...
            'Symbols',values,'Precoder',W,'TransmitPowerPerRE_W',repmat(epre,numel(values),1), ...
            'ConfiguredTotalPower_W',watts,'AggregateAntennaEPRE_W',epre, ...
            'MIBTransportBits',bits,'BCHCodeword',cw,'Lmax',timing.Lmax, ...
            'BlockSymbols0Based',selected-1,'BurstPlanSHA256',string(plan.PlanSHA256), ...
            'PhysicalPrecoderSHA256',string(sixgr.phy.mimo.MatrixContract.digest(W)), ...
            'SymbolSource',"native_nrPSS_nrSSS_nrBCH_nrPBCH_nrPBCHDMRS", ...
            'PhaseAssumption',string(p.ssbPhaseAssumption),'PowerPolicy',string(p.ssbPowerPolicy), ...
            'BeamPolicy',string(p.ssbBeamPolicy),'ReceptionQualified',false);
        row.SHA256=string(sixgr.util.sha256Hex(uint8(unicode2native( ...
            jsonencode(sixgr.util.jsonSafeValue(row)),'UTF-8'))));
        emissions=[emissions row]; %#ok<AGROW>
    end
end
end
