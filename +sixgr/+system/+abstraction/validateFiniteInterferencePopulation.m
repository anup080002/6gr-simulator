function validateFiniteInterferencePopulation(cfg,observation)
% Validate the configured modeled population at the calibrated-data consumer.
% Inclusion describes an enabled producer; an empty occasion is legitimate.
% Neither inclusion nor a nonempty population establishes PHY qualification.
policy=cfg.system.linkAbstraction.networkSpatial;
populations=["scheduled_shared_data_grants_only", ...
    "scheduled_shared_data_and_srs", ...
    "scheduled_shared_data_and_srs_and_csirs", ...
    "scheduled_shared_data_and_srs_and_csirs_and_pdcch"];
sources=["modeled_committed_finite_window_shared_data", ...
    "modeled_committed_finite_window_shared_data_and_srs", ...
    "modeled_committed_finite_window_shared_data_and_srs_and_csirs", ...
    "modeled_committed_finite_window_shared_data_and_srs_and_csirs_and_pdcch"];
population=string(policy.interferencePopulation);
assert(isscalar(population) && any(population==populations), ...
    'sixgr:abstraction:FiniteSpatialEvidence','Unsupported configured finite interference population.');
index=find(population==populations);
ssb=sixgr.util.structGet(policy,'ssbInterferenceEnabled',false);
assert(isBoolean(ssb) && (~logical(ssb) || index==4), ...
    'sixgr:abstraction:FiniteSpatialEvidence','SSB requires an explicit supported control population.');
expected=[index>=2 index>=3 index>=4 logical(ssb)];
source=sources(index);
if ssb, source=source+"_and_ssb"; end
pucch=sixgr.util.structGet(policy,'pucchInterferenceEnabled',false);
assert(isBoolean(pucch) && (~logical(pucch) || index>=2), ...
    'sixgr:abstraction:FiniteSpatialEvidence','PUCCH needs explicit finite native RS history.');
if pucch, source=source+"_and_pucch"; end
finite=observation.FiniteWindow;
assert(isscalar(string(finite.SourceClassification)) && string(finite.SourceClassification)==source && ...
    isfield(finite,'ReferenceObservationOnly') && isBoolean(finite.ReferenceObservationOnly) && ...
    ~finite.ReferenceObservationOnly && isfield(finite,'WaveformMeasured') && ...
    isBoolean(finite.WaveformMeasured) && ~finite.WaveformMeasured, ...
    'sixgr:abstraction:FiniteSpatialEvidence', ...
    'Require a data receive window with the exact configured modeled population, not reference-only or waveform truth.');
for k=1:4
    channels=["SRS","CSIRS","PDCCH","SSB"];
    flag=channels(k)+"InterferenceIncluded";
    rows=channels(k)+"EmissionPopulation";
    count=channels(k)+"EmissionCount";
    assert(isfield(finite,flag) && isBoolean(finite.(flag)) && finite.(flag)==expected(k) && ...
        isfield(observation,flag) && isBoolean(observation.(flag)) && observation.(flag)==expected(k) && ...
        isfield(finite,rows) && isstruct(finite.(rows)) && ...
        isfield(observation,count) && isequal(double(observation.(count)),double(numel(finite.(rows)))) && ...
        (expected(k) || isempty(finite.(rows))), ...
        'sixgr:abstraction:FiniteSpatialEvidence', ...
        '%s producer inclusion, retained population and exported count must agree with configuration.',channels(k));
end
% Legacy observations with this optional producer disabled may omit its
% fields. An enabled producer or an explicit claim must carry full evidence.
if pucch || isfield(finite,'PUCCHInterferenceIncluded') || isfield(observation,'PUCCHInterferenceIncluded')
    assert(isfield(finite,'PUCCHInterferenceIncluded') && isBoolean(finite.PUCCHInterferenceIncluded) && ...
        finite.PUCCHInterferenceIncluded==logical(pucch) && ...
        isfield(observation,'PUCCHInterferenceIncluded') && isBoolean(observation.PUCCHInterferenceIncluded) && ...
        observation.PUCCHInterferenceIncluded==logical(pucch) && ...
        isfield(finite,'PUCCHEmissionPopulation') && isstruct(finite.PUCCHEmissionPopulation) && ...
        isfield(observation,'PUCCHEmissionCount') && ...
        isequal(double(observation.PUCCHEmissionCount),double(numel(finite.PUCCHEmissionPopulation))) && ...
        (pucch || isempty(finite.PUCCHEmissionPopulation)), ...
        'sixgr:abstraction:FiniteSpatialEvidence','PUCCH inclusion, native population and count must agree.');
end
end
function valid=isBoolean(value)
valid=(islogical(value)||isnumeric(value)) && isscalar(value) && isreal(value) && ...
    isfinite(value) && any(value==[0 1]);
end
