function identity=networkReceiverCalibrationIdentity(cfg,direction,receiverType)
%NETWORKRECEIVERCALIBRATIONIDENTITY Bind curves to the replay receiver recipe.
% This is a conservative baseline-config identity, not proof of execution or
% statistical qualification. Frozen grant coding/resources have their own
% key. Keep the complete PHY baseline so unlisted receiver settings cannot
% silently reuse a curve. Carrier realization clocks are not a recipe.
arguments
    cfg (1,1) struct
    direction (1,1) string {mustBeMember(direction,["DL","UL"])}
    receiverType (1,1) string {mustBeMember(receiverType,["lmmse","zf"])}
end
phy=cfg.phy;
phy.carrier=rmfield(phy.carrier,intersect(fieldnames(phy.carrier),{'NFrame','NSlot'}));
% replayGrant explicitly selects the non-fast channel-estimation path.
phy.rx.useFastChannelEstMex=false;
identity=struct('Schema',"sixgr.network_waveform_receiver_recipe/v3", ...
    'Direction',direction,'SpatialPredictor',receiverType, ...
    'SINRPredictorModel',sixgr.system.abstraction.resolveNetworkSINRModel(cfg), ...
    'PredictorPlane',"scheduled_nominal_fft_before_receiver_sync", ...
    'WaveformEntryPoint',"sixgr.system.waveform.replayGrant", ...
    'PHYBaseline',phy,'UseMex',logical(sixgr.util.structGet(cfg,'run.useMex',false)), ...
    'MATLABVersion',string(version),'MaxIterations',sixgr.phy.phycode.resolveLDPCMaxIterations(cfg), ...
    'LDPCAlgorithm',string(sixgr.util.structGet(cfg,'phy.ldpc.algorithm','Normalized min-sum')), ...
    'FastAWGNPath',false,'IterationCapOverride',0,'UseGPU',false);
identity.SHA256=string(sixgr.util.sha256Hex(uint8(unicode2native( ...
    jsonencode(sixgr.util.jsonSafeValue(identity)),'UTF-8'))));
identity.ProfileID="grant_receiver_"+identity.SHA256;
end
