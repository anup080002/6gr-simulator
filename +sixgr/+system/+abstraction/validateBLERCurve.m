function validateBLERCurve(c,p)
% Validate conditional probabilities and separately retained validation counts.
fields={'CurveID','Key','RVSequence','SINRAxes_dB','BetaLinear', ...
    'TrialCount','ErrorCount','ValidationTrialCount','ValidationErrorCount'};
assert(isstruct(c) && isscalar(c) && all(isfield(c,fields)), ...
    'sixgr:abstraction:CalibrationSchema','Conditional BLER curve schema is incomplete.');
validateattributes(c.BetaLinear,{'numeric'},{'scalar','real','finite','positive'});
assert(isfield(c.Key,'EffectiveSINRMethod') && ...
    any(string(c.Key.EffectiveSINRMethod)==["calibrated_eesm","calibrated_miesm"]), ...
    'sixgr:abstraction:CalibrationSchema','Calibration must identify its actual effective-SINR mapping.');
if string(c.Key.EffectiveSINRMethod)=="calibrated_miesm"
    assert(isfield(c,'MILookup'),'sixgr:abstraction:CalibrationSchema','MIESM needs its retained modulation-specific MI table.');
    sixgr.phy.rsla.MIESMMapper.validateLookup(c.MILookup);
    token=upper(string(c.Key.Modulation));
    order=str2double(erase(token,"QAM"));
    if token=="QPSK", order=4; elseif any(token==["BPSK","PI/2-BPSK"]), order=2; end
    assert(isfinite(order) && order==c.MILookup.ModulationOrder, ...
        'sixgr:abstraction:CalibrationSchema','The MI curve must match the actual grant modulation order.');
    assert(c.MILookup.BetaLinear==c.BetaLinear, ...
        'sixgr:abstraction:CalibrationSchema','Curve and MI mapping must share the calibrated beta.');
end
rv=double(c.RVSequence(:).');
assert(~isempty(rv) && all(ismember(rv,0:3)) && numel(c.SINRAxes_dB)==numel(rv), ...
    'sixgr:abstraction:CalibrationSchema','One SINR axis per retained HARQ attempt is required.');
shape=zeros(1,numel(rv));
for k=1:numel(rv)
    axis=double(c.SINRAxes_dB{k});
    assert(isvector(axis) && numel(axis)>=2 && all(isfinite(axis)) && all(diff(axis)>0), ...
        'sixgr:abstraction:CalibrationGrid','Each SINR axis must be finite and strictly increasing.');
    shape(k)=numel(axis);
end
if numel(shape)==1, shape=[shape 1]; end
supported=true(shape);
if isfield(c,'SupportedMask')
    assert((islogical(c.SupportedMask) || ...
        (isnumeric(c.SupportedMask) && all(ismember(c.SupportedMask(:),[0 1])))) && ...
        isequal(size(c.SupportedMask),shape), ...
        'sixgr:abstraction:CalibrationGrid','SupportedMask must match the measured grid.');
    supported=logical(c.SupportedMask);
end
assert(any(supported,'all'),'sixgr:abstraction:CalibrationCoverage', ...
    'A curve needs at least one measured, statistically accepted grid cell.');
for name=["TrialCount","ErrorCount","ValidationTrialCount","ValidationErrorCount"]
    v=c.(name);
    assert(isnumeric(v) && isreal(v) && all(isfinite(v),'all') && ...
        all(v==fix(v),'all') && all(v>=0,'all') && isequal(size(v),shape), ...
        'sixgr:abstraction:CalibrationGrid','Count tensors must cover the complete SINR-history grid.');
end
assert(all(c.TrialCount(supported)>=p.minimumCalibrationTrials) && ...
    sum(c.ErrorCount(supported))>=p.minimumCalibrationErrors && ...
    all(c.ErrorCount<=c.TrialCount,'all') && ...
    all(c.ValidationTrialCount(supported)>=p.minimumValidationTrials) && ...
    all(c.ValidationErrorCount<=c.ValidationTrialCount,'all'), ...
    'sixgr:abstraction:CalibrationStatistics','Incomplete calibration/validation populations.');
for index=find(supported(:)).'
    [lo,hi]=sixgr.lls.stats.wilsonInterval(double(c.ErrorCount(index)), ...
        double(c.TrialCount(index)),double(p.calibrationConfidenceLevel));
    [vLo,vHi]=sixgr.lls.stats.wilsonInterval(double(c.ValidationErrorCount(index)), ...
        double(c.ValidationTrialCount(index)),double(p.calibrationConfidenceLevel));
    assert((hi-lo)/2<=p.maximumCalibrationWilsonHalfWidth && ...
        (vHi-vLo)/2<=p.maximumCalibrationWilsonHalfWidth, ...
        'sixgr:abstraction:CalibrationStatistics', ...
        'A supported cell needs sufficiently precise independent waveform BLER intervals.');
end
fit=c.ErrorCount./c.TrialCount;
heldout=c.ValidationErrorCount./c.ValidationTrialCount;
assert(all(abs(fit(supported)-heldout(supported))<=p.maximumValidationAbsoluteBLERError), ...
    'sixgr:abstraction:CalibrationValidation','Independent validation exceeds the configured absolute BLER error.');
end
