function validateFeedbackCompletionClock(o,now)
% Validate delayed reference completion, not merely an older source label.
validateattributes(now,{'numeric'},{'scalar','integer','nonnegative','finite'});
validateattributes(o.SourceAbsoluteSlot0,{'numeric'},{'scalar','integer','nonnegative','finite'});
id='sixgr:abstraction:FeedbackCaptureClock';
if ~isfield(o,'ReferenceCompletionEvidence')
    assert(o.SourceAbsoluteSlot0==now,id, ...
        'An older reference source requires explicit committed receive-completion evidence.');
    return;
end
assert(all(isfield(o,{'CompletionAbsoluteSlot0','PublicationAbsoluteSlot0', ...
    'AvailableAbsoluteSlot0','DisturbanceAssumption','Coordinates0Based'})),id, ...
    'Incomplete delayed reference clock/observation binding.');
e=o.ReferenceCompletionEvidence;
assert(isstruct(e) && isscalar(e) && all(isfield(e, ...
    {'Support','ReceiveWindow','SourceObservationSHA256','WaveformMeasured','PrimaryStudyAccepted'})), ...
    id,'Require the retained reference source and committed receive-window evidence.');
s=e.Support; w=e.ReceiveWindow;
assert(o.SourceAbsoluteSlot0<=now && o.CompletionAbsoluteSlot0==now && ...
    o.PublicationAbsoluteSlot0==now && o.AvailableAbsoluteSlot0>=now+1 && ...
    string(o.DisturbanceAssumption)=="finite_committed_shared_data" && ...
    s.TransmissionTTI==o.SourceAbsoluteSlot0+1 && ...
    s.RequiredCommittedThroughTTI==now+1 && s.ReadAtCommittedTTI==now+1 && s.Available && ...
    s.RequiredCommittedThroughTTI==s.TransmissionTTI+s.ReceiveSlotSupport.RequiredFollowingSlots && ...
    w.ObservationTTI==s.TransmissionTTI && w.RequiredCommittedThroughTTI==now+1 && ...
    w.ReadAtCommittedTTI==now+1 && w.HistoryComplete && ...
    isequaln(w.ReceiveSlotSupport,s.ReceiveSlotSupport) && ...
    isequal(w.Coordinates0Based,double(o.Coordinates0Based)) && ...
    isequal(w.TTIs,max(1,s.TransmissionTTI-s.ReceiveSlotSupport.RequiredPreviousSlots):now+1) && ...
    ~e.WaveformMeasured && ~e.PrimaryStudyAccepted && ...
    ~isempty(regexp(char(e.SourceObservationSHA256),'^[0-9a-fA-F]{64}$','once')), ...
    id,'Reference source, completion, delivery and committed window do not agree.');
if isfield(o,'ReportAbsoluteSlot0')
    assert(o.ReferenceAvailableAtSlot0>=now+1 && ...
        o.ReportAbsoluteSlot0>=o.ReferenceAvailableAtSlot0 && ...
        o.AvailableAbsoluteSlot0>o.ReportAbsoluteSlot0,id, ...
        'CSI reporting cannot precede reference completion/processing or transport delivery.');
end
end
