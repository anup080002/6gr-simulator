function bound=materializeModeledPUCCH(cfg,planned,reference,now)
% Bind SLS ideal-channel power without writing LLS RuntimeMeasured* fields.
% Resource/report validation and native coding remain canonical. This state
% is not a received TPC command or a physical pathloss measurement.
assert(strcmpi(string(cfg.system.phyBackend),'calibrated_link_abstraction') && ...
    ~sixgr.rf.isNormalizedFixedSNRPowerReference(cfg), ...
    'sixgr:abstraction:PUCCHModeledPowerAuthority','Only absolute-power, explicitly modeled SLS may use this binding.');
assert(isa(planned.Plan,'sixgr.phy.pucch.PUCCHResourcePlan') && ...
    isa(planned.Report,'sixgr.phy.pucch.UCIReport'), ...
    'sixgr:phy:pucch:MissingUCIReportContext','Require a typed resource plan and exact report.');
d=planned.Plan.Data;
rrc=sixgr.phy.pucch.PUCCHConfigBuilder.receiverConfiguration(cfg,d);
assert(rrc.Digest==planned.Plan.RRCContextDigest && planned.Report.Digest==planned.Plan.ReportDigest && ...
    d.DueSlot==now+1,'sixgr:phy:pucch:StaleConfiguration','Revalidate installed resource/report identity and transmission clock.');
policy=sixgr.util.structGet(cfg,'system.linkAbstraction.dynamicPUCCH.powerReference',struct());
assert(logical(sixgr.util.structGet(policy,'enabled',false)) && isstruct(reference) && isscalar(reference) && ...
    isfield(reference,'Available') && reference.Available && isfield(reference,'BindingSHA256'), ...
    'sixgr:abstraction:MissingModeledPowerReference','A positive transmission requires the completed configured CSI-RS reference.');
assert(reference.BindingSHA256==localHash(rmfield(reference,'BindingSHA256')) && ...
    reference.ExecutionID==string(cfg.run.executionID) && reference.UEIndex==d.UEID && ...
    reference.RNTI==d.RNTI && reference.ServingCell==d.ServingCell && ...
    reference.ReferenceSignalID==policy.referenceSignalID && ...
    reference.PathlossReferenceRSID==policy.pathlossReferenceRSID && ...
    reference.ReferenceSignalType==string(policy.referenceSignalType) && ...
    reference.SourceClassification==string(policy.sourceClassification) && ...
    ~reference.WaveformMeasured && reference.KnownAtAbsoluteSlot0==now && ...
    reference.CapturedAtAbsoluteSlot0<now && reference.ReferenceAvailableAtSlot0<=now && ...
    reference.AgeSlots==now-reference.SourceAbsoluteSlot0 && reference.AgeSlots<=policy.maximumAgeSlots && ...
    reference.FilterCoefficient==policy.filterCoefficient && reference.ReceivePolicy==string(policy.receivePolicy), ...
    'sixgr:abstraction:PowerReferenceIdentity','No stale, cross-UE, mutated or differently configured power reference.');
section=cfg.validation.pucch_resources; p=section.power_control;
assert(p.pathloss_reference_rs_id==policy.pathlossReferenceRSID, ...
    'sixgr:abstraction:PowerReferenceIdentity','Bind the configured PUCCH pathloss-reference index, not a coincident CSI resource number.');
power=sixgr.phy.pucch.PUCCHPowerControlState(struct( ...
    'Mu',log2(cfg.phy.carrier.SubcarrierSpacing/15),'MRB',planned.Plan.Resource.Data.NumPRBs, ...
    'BandwidthSource',"selected_pucch_resource_and_active_carrier_scs", ...
    'P0dBm',p.p0_dbm,'PathlossdB',reference.PathlossdB,'ConfiguredPathlossdB',p.pathloss_db, ...
    'DeltaFdB',p.delta_f_db,'DeltaTFdB',p.delta_tf_db, ...
    'ClosedLoopAdjustmentdB',p.closed_loop_adjustment_db,'PCMAXdBm',p.pcmax_dbm, ...
    'PathlossReferenceRSID',p.pathloss_reference_rs_id, ...
    'TPCCommandSource',"configured_SLS_adjustment_not_received_TPC:"+string(p.tpc_command_source), ...
    'StateID',"SLS-MODELED-POWER-"+reference.BindingSHA256, ...
    'PathlossSource',reference.SourceClassification,'PathlossReferenceRS', ...
    reference.ReferenceSignalType+"-"+reference.ReferenceSignalID, ...
    'RuntimeMeasuredPathlossUsed',false,'ModeledReference',reference));
items=section.spatial_relations;
assert(numel(unique([items.id]))==numel(items) && isscalar(unique([items.active_id])), ...
    'sixgr:phy:pucch:AmbiguousSpatialRelation','Require one installed active spatial relation.');
s=items([items.id]==items(1).active_id);
assert(isscalar(s),'sixgr:phy:pucch:InactiveSpatialRelation','The selected relation is not installed.');
spatial=sixgr.phy.pucch.PUCCHSpatialRelationState(struct( ...
    'SpatialRelationID',s.id,'ActiveSpatialRelationID',s.active_id, ...
    'ReferenceSignalType',string(s.reference_signal_type),'ReferenceSignalID',s.reference_signal_id, ...
    'PathlossReferenceRSID',s.pathloss_reference_rs_id,'P0PUCCHID',s.p0_pucch_id, ...
    'ClosedLoopIndex',s.closed_loop_index,'StateAgeSlots',s.state_age_slots, ...
    'MaximumAgeSlots',s.maximum_age_slots,'SelectedBeamID',s.selected_beam_id,'AppliedBeamID',s.applied_beam_id));
assert(s.pathloss_reference_rs_id==p.pathloss_reference_rs_id, ...
    'sixgr:abstraction:PowerReferenceIdentity','Active spatial relation and PUCCH power-reference index disagree.');
assignment=sixgr.phy.pucch.PUCCHTransmissionAssignment.fromResourcePlan(planned.Plan,power,spatial);
bound=struct('Assignment',assignment,'Report',planned.Report,'RRCContext',rrc);
end
function h=localHash(v)
h=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(sixgr.util.jsonSafeValue(v)),'UTF-8'))));
end
