function out=evaluateFiniteOFDMSpatialSINR(observation,externalCovariance,receiverType)
% Finite-window desired channel, its other-RE leakage, and external noise.
% The observation contains already power-weighted layer responses. Do not
% renormalize them or treat its TOTAL covariance as external interference.
% This is still a model prediction, never a measured waveform SINR.
arguments
    observation (1,1) struct
    externalCovariance {mustBeNumeric,mustBeFinite,mustBeNonempty}
    receiverType (1,1) string {mustBeMember(receiverType,["lmmse","zf"])}="lmmse"
end
required={'SameResourceEffectiveChannel','SameResourceChannelIncludesTransmitPower', ...
    'OtherResourceCovariance','Covariance','Coordinates0Based','SourceClassification', ...
    'BoundaryPolicy','WithinWindowISIICIIncluded','FullNetworkInterferenceQualified', ...
    'CommonControlInterferenceQualified','StatisticalBLERQualified','PrimaryStudyAccepted'};
assert(all(isfield(observation,required)) && ...
    isequal(observation.SameResourceChannelIncludesTransmitPower,true) && ...
    isequal(observation.WithinWindowISIICIIncluded,true) && ...
    string(observation.SourceClassification)=="modeled_finite_filter_independent_symbol_covariance" && ...
    string(observation.BoundaryPolicy)=="explicit_zero_outside_declared_observation_window" && ...
    isequal(observation.FullNetworkInterferenceQualified,false) && ...
    isequal(observation.CommonControlInterferenceQualified,false) && ...
    isequal(observation.StatisticalBLERQualified,false) && isequal(observation.PrimaryStudyAccepted,false), ...
    'sixgr:abstraction:FiniteSpatialEvidence','Require the explicit finite-window modeled population, without qualification claims.');
G=observation.SameResourceEffectiveChannel;
other=observation.OtherResourceCovariance; total=observation.Covariance;
validateattributes(G,{'double'},{'finite','nonempty'});
validateattributes(other,{'double'},{'finite','nonempty'});
validateattributes(total,{'double'},{'finite','nonempty'});
[nr,~,nres]=size(G); R=double(externalCovariance);
assert(ndims(G)<=3 && ndims(other)<=3 && ndims(total)<=3 && ndims(R)<=3 && ...
    size(other,1)==nr && size(other,2)==nr && size(other,3)==nres && ...
    isequal(size(total),size(other)) && size(R,1)==nr && size(R,2)==nr && ...
    ismember(size(R,3),[1 nres]) && size(observation.Coordinates0Based,1)==nres, ...
    'sixgr:abstraction:SpatialDimensions','Finite-channel populations must share the exact RX/resource dimensions.');
combined=complex(zeros(size(other)));
for k=1:nres
    noise=R(:,:,min(k,size(R,3))); scale=norm(noise,'fro');
    assert(scale>0 && norm(noise-noise','fro')<=1e-10*scale, ...
        'sixgr:abstraction:Covariance','External noise/interference must be Hermitian positive definite.');
    [~,failed]=chol(noise);
    assert(failed==0,'sixgr:abstraction:Covariance','No hidden loading may repair invalid external noise.');
    leak=other(:,:,k); scale=norm(leak,'fro');
    assert(norm(leak-leak','fro')<=1e-12*scale && ...
        all(real(eig((leak+leak')/2))>=-1e-12*scale), ...
        'sixgr:abstraction:FiniteSpatialPartition','Other-RE covariance must be positive semidefinite; no clipping is allowed.');
    reconstructed=G(:,:,k)*G(:,:,k)'+leak;
    assert(norm(reconstructed-total(:,:,k),'fro')<=1e-12*max(norm(reconstructed,'fro'),norm(total(:,:,k),'fro')), ...
        'sixgr:abstraction:FiniteSpatialPartition','Useful same-RE layers plus other-RE leakage must reproduce total covariance exactly once.');
    combined(:,:,k)=noise+leak;
end
out=sixgr.system.abstraction.evaluateEffectiveSpatialSINR(G,combined,receiverType);
out.Source="modeled_finite_window_spatial_"+receiverType;
out.BoundaryPolicy=observation.BoundaryPolicy;
out.WithinWindowISIICIIncluded=true;
out.FullNetworkInterferenceQualified=false;
out.StatisticalBLERQualified=false;
out.PrimaryStudyAccepted=false;
end
