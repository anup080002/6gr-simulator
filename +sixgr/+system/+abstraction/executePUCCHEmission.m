function [emission,tx]=executePUCCHEmission(carrier,assignment,report,binding)
% Execute the canonical transmitter, then expose its symbols to finite SLS.
% Native TX does not qualify the modeled control decisions or a receiver.
% Power is the assignment's applied power, never UE PCMAX or a reservation.
assert(isa(assignment,'sixgr.phy.pucch.PUCCHTransmissionAssignment') && ...
    isa(report,'sixgr.phy.pucch.UCIReport'), ...
    'sixgr:abstraction:PUCCHEmissionAssignment','Require an actual typed transmitter assignment/report.');
required={'AbsoluteSlot0','UEIndex','RNTI','ServingCellID','Precoder', ...
    'SpatialStateDigest','SourceClassification'};
assert(isstruct(binding) && isscalar(binding) && all(isfield(binding,required)), ...
    'sixgr:abstraction:PUCCHEmissionBinding','Bind the current UE, clock and spatial matrix explicitly.');
slot=binding.AbsoluteSlot0;
validateattributes(slot,{'numeric'},{'scalar','integer','nonnegative','finite'});
d=assignment.Data;
assert(slot==assignment.DueSlot-1 && binding.UEIndex==d.UEID && ...
    binding.RNTI==d.RNTI && binding.ServingCellID==d.ServingCell && ...
    carrier.NSlot==mod(slot,carrier.SlotsPerFrame) && ...
    carrier.NFrame==mod(floor(slot/carrier.SlotsPerFrame),1024), ...
    'sixgr:abstraction:PUCCHEmissionIdentity','Emission must match assignment ownership and the actual carrier clock.');
assert(isscalar(string(binding.SpatialStateDigest)) && ...
    string(binding.SpatialStateDigest)==assignment.SpatialRelationState.Digest, ...
    'sixgr:abstraction:PUCCHEmissionSpatialBinding','The antenna matrix must bind the active spatial-relation state.');
source=string(binding.SourceClassification);
assert(isscalar(source) && ~ismissing(source) && any(source== ...
    ["modeled_SLS_ideal_delayed_control","declared_component_fixture_not_study_result"]), ...
    'sixgr:abstraction:PUCCHEmissionSource','Native symbols do not make modeled or fixture UCI waveform-decoded truth.');
obligationID=""; obligationSHA256="";
if isfield(binding,'Obligation')
    o=binding.Obligation;
    assert(isstruct(o) && isscalar(o) && all(isfield(o, ...
        {'ResourceID','AbsoluteSlot0','UEIndex','RNTI','CellID','Transport'})) && ...
        isscalar(string(o.ResourceID)) && ~ismissing(string(o.ResourceID)) && strlength(string(o.ResourceID))>0 && ...
        o.AbsoluteSlot0==slot && o.UEIndex==binding.UEIndex && o.RNTI==binding.RNTI && ...
        o.CellID==binding.ServingCellID && string(o.Transport)=="PUCCH", ...
        'sixgr:abstraction:PUCCHEmissionObligation','Bind the independently owned obligation for this UE/cell/occasion.');
    obligationID=string(o.ResourceID);
    obligationSHA256=string(sixgr.util.sha256Hex(uint8(unicode2native( ...
        jsonencode(sixgr.util.jsonSafeValue(o)),'UTF-8'))));
else
    assert(source=="declared_component_fixture_not_study_result", ...
        'sixgr:abstraction:PUCCHEmissionObligation','Production modeled emissions require their owned UCI obligation.');
end
% This is lineage only. The independently scheduled receive hypothesis is
% not used to construct bits or force transmitter/receiver layouts to agree.
W=double(binding.Precoder);
assert(ismatrix(W) && size(W,1)>=1 && size(W,2)==1 && all(isfinite(W),'all') && ...
    abs(sum(abs(W).^2,'all')-1)<1e-12, ...
    'sixgr:abstraction:PUCCHEmissionPrecoder','One logical PUCCH stream requires an explicit unit-norm antenna vector.');
spatial=assignment.SpatialRelationState.Data;
assert(isfield(spatial,'PhysicalPrecoderSHA256') && ...
    isscalar(string(spatial.PhysicalPrecoderSHA256)) && ...
    string(spatial.PhysicalPrecoderSHA256)==string(sixgr.phy.mimo.MatrixContract.digest(W)), ...
    'sixgr:abstraction:PUCCHEmissionSpatialBinding', ...
    'The typed spatial state must bind this exact antenna vector, not only a beam label.');
power=sixgr.phy.pucch.PUCCHPowerController.resolve(assignment.PowerControlState);
assert(~logical(sixgr.util.structGet(power,'NormalizedPowerReference',false)) && ...
    isfinite(power.AppliedPowerdBm), ...
    'sixgr:abstraction:PUCCHEmissionAbsolutePower','Normalized unit-Es samples cannot create a watt-valued SLS emitter.');
tx=sixgr.phy.pucch.PUCCHTransmitter.transmit(carrier,assignment,report);
emission=struct([]);
if ~tx.TransmissionPresent, return; end
K=12*carrier.NSizeGrid; L=carrier.SymbolsPerSlot;
assert(size(tx.Grid,3)==1,'sixgr:abstraction:PUCCHEmissionPrecoder', ...
    'This binding is for one logical PUCCH stream, not an inferred multiport mapping.');
flat=reshape(double(tx.Grid),K*L,1); occupied=find(flat~=0);
[k,l]=ind2sub([K L],occupied); coords=[k-1 l-1]; symbols=flat(occupied);
active=assignment.Resource.Data.StartSymbol+(0:assignment.Resource.Data.NumSymbols-1);
assert(~isempty(occupied) && all(ismember(coords(:,2),active)), ...
    'sixgr:abstraction:PUCCHEmissionResource','Retain exactly the native data/DMRS resource population.');
% A single gain is applied by the canonical TX across the occasion. Preserve
% its per-symbol variation, DMRS/data ratios and phase; never normalize each
% symbol separately. The finite operator uses sum-of-RE power in watts.
energy=accumarray(l,abs(symbols).^2,[L 1]);
meanEnergy=mean(energy(active+1));
watts=10^((power.AppliedPowerdBm-30)/10);
assert(isfinite(meanEnergy) && meanEnergy>0 && isfinite(watts) && watts>0, ...
    'sixgr:abstraction:PUCCHEmissionPower','A physical emission needs positive finite native energy and power.');
perRE=repmat(watts/meanEnergy,numel(occupied),1);
antennaWaveform=double(tx.Waveform)*W.';
[measured,~,reference]=sixgr.rf.measureActiveOFDMTotalPower(antennaWaveform, ...
    struct('OFDM',tx.OFDMInfo),'ActiveSymbolIndices',active);
assert(string(reference.ReferenceDomain)=="specified_active_ofdm_symbols_excluding_cp" && ...
    abs(measured/1000-watts)<=1e-10*watts, ...
    'sixgr:abstraction:PUCCHEmissionPower','Native sample-domain power must close after the spatial mapping.');
tx.AntennaWaveform=antennaWaveform;
emission=struct('SourceTTI',slot+1,'AbsoluteSlot0',slot,'UEIndex',binding.UEIndex, ...
    'ServingCellID',binding.ServingCellID,'RNTI',binding.RNTI, ...
    'ResourceID',assignment.Resource.ID,'Signal',"PUCCH", ...
    'ObligationID',obligationID,'ObligationSHA256',obligationSHA256, ...
    'Coordinates0Based',coords,'Symbols',symbols,'Precoder',W, ...
    'TransmitPowerPerRE_W',perRE,'AppliedTotalPower_W',watts, ...
    'PowerPolicy',"typed_PUCCH_power_control_active_symbol_mean", ...
    'PowerEvidence',tx.Power,'PowerControlEvidence',assignment.PowerControlState.Data, ...
    'SpatialEvidence',assignment.SpatialRelationState.Data, ...
    'SpatialStateDigest',assignment.SpatialRelationState.Digest, ...
    'AssignmentDigest',assignment.Digest,'ReportDigest',report.Digest, ...
    'SymbolSource',"canonical_PUCCHTransmitter_native_UCI_data_and_DMRS", ...
    'PhaseAssumption',"native_sequence_phase_at_committed_epoch", ...
    'SourceClassification',source,'NativeWaveformExecuted',true, ...
    'PhysicalReceptionQualified',false,'RFImpairmentsApplied',false, ...
    'ElementPatternsApplied',false,'WaveformSHA256',tx.WaveformSHA256, ...
    'AntennaWaveformSHA256',string(sixgr.phy.mimo.MatrixContract.digest(antennaWaveform)));
emission.SHA256=string(sixgr.util.sha256Hex(uint8(unicode2native( ...
    jsonencode(sixgr.util.jsonSafeValue(emission)),'UTF-8'))));
end
