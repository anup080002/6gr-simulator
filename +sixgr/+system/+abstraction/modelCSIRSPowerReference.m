function reference=modelCSIRSPowerReference(cfg,o,emission)
% Ideal SLS port-3000 reference on the ACTUAL native CSI-RS RE population.
% TS 38.215 5.1.2: linear received-power averaging, not mean complex H.
% This is channel-model evaluation, never a noisy waveform measurement.
reference=struct([]);
p=sixgr.util.structGet(cfg,'system.linkAbstraction.dynamicPUCCH.powerReference',struct());
if ~logical(sixgr.util.structGet(p,'enabled',false)), return; end
assert(string(p.researchClass)=="optional_research_experiment" && ...
    string(p.referenceSignalType)=="CSI-RS" && p.antennaPort==3000 && ...
    string(p.receivePolicy)=="strongest_physical_receive_branch" && p.filterCoefficient==0 && ...
    string(p.sourceClassification)=="modeled_ideal_csirs_power_not_waveform_measurement", ...
    'sixgr:abstraction:PowerReferencePolicy', ...
    'Declare ideal port-3000 branch-selection RSRP and explicit fc0 filtering.');
validateattributes(p.referenceSignalID,{'numeric'},{'scalar','integer','nonnegative','finite'});
validateattributes(p.pathlossReferenceRSID,{'numeric'},{'scalar','integer','nonnegative','finite'});
validateattributes(p.maximumAgeSlots,{'numeric'},{'scalar','integer','positive','finite'});
assert(isscalar(emission) && isfield(emission,'SHA256') && ...
    string(emission.SHA256)==localHash(rmfield(emission,'SHA256')) && ...
    emission.Signal=="CSI-RS" && emission.ServingCellID==o.ServingCell && ...
    emission.AbsoluteSlot0==o.SourceAbsoluteSlot0 && emission.ResourceID==o.ReferenceResourceID && ...
    string(emission.SHA256)==string(o.ReferenceEmissionSHA256), ...
    'sixgr:abstraction:PowerReferenceEmission','Require the committed native CSI-RS emission, not a reservation.');
if emission.ResourceID~=p.referenceSignalID, return; end
B=o.PortToElementMatrix; H=o.ChannelEstimate;
assert(size(H,2)==size(B,2) && norm(B'*B-eye(size(B,2)),'fro')<1e-10 && ...
    string(sixgr.phy.mimo.MatrixContract.digest(B))==string(emission.PhysicalPrecoderSHA256), ...
    'sixgr:abstraction:PowerReferenceBasis','Reference channel and native TX must use the same semi-unitary CSI port basis.');
% Undo ONLY the finite-operator interface's precoder, then project onto the
% executed port basis. This recovers native logical symbols including CDM;
% aggregate multiport EPRE is NOT port-3000 EPRE.
physical=emission.Symbols*emission.Precoder.';
logicalSymbols=physical*conj(B);
assert(norm(logicalSymbols*B.'-physical,'fro')<=1e-10*norm(physical,'fro'), ...
    'sixgr:abstraction:PowerReferenceBasis','The CSI emitter lies outside its declared logical basis.');
[present,indices]=ismember(o.Coordinates0Based,emission.Coordinates0Based,'rows');
assert(all(present) && size(H,3)==numel(indices) && ...
    numel(unique(indices))==size(emission.Coordinates0Based,1), ...
    'sixgr:abstraction:PowerReferencePopulation','Use the same complete actual reference RE population.');
s=logicalSymbols(indices,1);
active=abs(s)>1e-10*max(abs(s)); % Reject projection roundoff on other ports' REs.
assert(any(active),'sixgr:abstraction:PowerReferencePopulation','Port 3000 has no transmitted samples.');
tx=abs(s(active)).^2.*emission.TransmitPowerPerRE_W(indices(active));
gain=abs(reshape(H(:,1,active),size(H,1),[])).^2;
branches=mean(gain.*tx(:).',2);
[rx,branch]=max(branches); epRE=mean(tx);
assert(all(isfinite(tx) & tx>0) && isfinite(rx) && rx>0, ...
    'sixgr:abstraction:PowerReferencePower','Native reference requires finite positive TX and received power.');
reference=struct('ReferenceSignalType',"CSI-RS",'ReferenceSignalID',emission.ResourceID, ...
    'PathlossReferenceRSID',p.pathlossReferenceRSID, ...
    'AntennaPort',3000,'TransmitEPRE_W',epRE,'ReceiveBranchRSRP_W',branches, ...
    'SelectedReceiveBranch0',branch-1,'RSRP_W',rx,'RSRP_dBm',10*log10(rx)+30, ...
    'PathlossdB',10*log10(epRE/rx),'ReferenceRECount',nnz(active), ...
    'ReferenceCoordinates0Based',o.Coordinates0Based(active,:), ...
    'ReferenceEmissionSHA256',string(emission.SHA256), ...
    'PortBasisSHA256',string(emission.PhysicalPrecoderSHA256), ...
    'ExecutionID',string(o.ExecutionID),'UEIndex',o.UEIndex,'RNTI',o.RNTI,'ServingCell',o.ServingCell, ...
    'SourceAbsoluteSlot0',o.SourceAbsoluteSlot0, ...
    'ReceivePolicy',string(p.receivePolicy),'FilterCoefficient',p.filterCoefficient, ...
    'SourceClassification',string(p.sourceClassification), ...
    'WaveformMeasured',false,'PhysicalEstimationQualified',false);
reference.SHA256=localHash(reference);
end
function h=localHash(v)
h=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(sixgr.util.jsonSafeValue(v)),'UTF-8'))));
end
