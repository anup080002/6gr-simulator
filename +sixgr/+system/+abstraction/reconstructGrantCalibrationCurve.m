function [curve,fit]=reconstructGrantCalibrationCurve(spec,policy,root)
%RECONSTRUCTGRANTCALIBRATIONCURVE Authenticate inputs and redo qualification.
% AWGN conditional counts remain AWGN counts. A separately fitted and
% independently validated fading mapping owns the target runtime key.
arguments
    spec (1,1) struct
    policy (1,1) struct
    root (1,1) string
end
required={'CurveID','ReferenceFolder','TargetFolder','ReferenceManifestSHA256', ...
    'TargetManifestSHA256','ReferenceKey','TargetKey','RVSequence','FittingPolicy'};
assert(all(isfield(spec,required)) && strlength(strtrim(string(spec.CurveID)))>0, ...
    'sixgr:abstraction:GrantCalibrationSpecification','Incomplete grant-backed curve specification.');
q=spec.FittingPolicy;
requiredPolicy={'minimum_conditional_trials','confidence_level','maximum_wilson_half_width', ...
    'maximum_validation_absolute_bler_error','beta_linear_bounds','beta_log_grid_count', ...
    'minimum_beta_objective_contrast'};
assert(all(isfield(q,requiredPolicy)), ...
    'sixgr:abstraction:GrantCalibrationPolicy','Explicit frozen fitting/statistical policy required.');
validateattributes(q.minimum_conditional_trials,{'numeric'},{'scalar','integer','positive','finite'});
validateattributes(q.confidence_level,{'numeric'},{'scalar','>',0,'<',1,'finite'});
validateattributes(q.maximum_wilson_half_width,{'numeric'},{'scalar','>',0,'<',0.5,'finite'});
validateattributes(q.maximum_validation_absolute_bler_error,{'numeric'},{'scalar','>',0,'<',1,'finite'});
validateattributes(q.beta_linear_bounds,{'numeric'},{'vector','numel',2,'positive','finite'});
validateattributes(q.beta_log_grid_count,{'numeric'},{'scalar','integer','>=',3,'finite'});
validateattributes(q.minimum_beta_objective_contrast,{'numeric'},{'scalar','positive','finite'});
assert(diff(q.beta_linear_bounds)>0 && ...
    q.minimum_conditional_trials>=max(policy.minimumCalibrationTrials,policy.minimumValidationTrials) && ...
    q.confidence_level>=policy.calibrationConfidenceLevel && ...
    q.maximum_wilson_half_width<=policy.maximumCalibrationWilsonHalfWidth && ...
    q.maximum_validation_absolute_bler_error<=policy.maximumValidationAbsoluteBLERError, ...
    'sixgr:abstraction:GrantCalibrationPolicy', ...
    'Fitting/held-out gates cannot be weaker than the SLS installation policy.');
reference=localFolder(root,spec.ReferenceFolder,spec.ReferenceManifestSHA256);
target=localFolder(root,spec.TargetFolder,spec.TargetManifestSHA256);
fit=sixgr.calibration.fitGrantCalibrationCollections(reference,target, ...
    spec.ReferenceKey,spec.TargetKey,double(spec.RVSequence(:).'),q);
assert(fit.FittingPassed && fit.ReferenceValidation.Passed && ...
    fit.ChannelEvolution=="persistent_link_absolute_slot", ...
    'sixgr:abstraction:GrantCalibrationQualification', ...
    'Require independently qualified curves with the persistent network channel history.');
curve=struct('CurveID',string(spec.CurveID),'Key',fit.RuntimeKey, ...
    'RVSequence',fit.RVSequence,'HARQSlotOffsets0',fit.HARQSlotOffsets0, ...
    'ChannelEvolution',fit.ChannelEvolution, ...
    'SINRAxes_dB',{fit.Reference.SINRAxes_dB},'BetaLinear',fit.BetaLinear, ...
    'TrialCount',fit.Reference.TrialCount,'ErrorCount',fit.Reference.ErrorCount, ...
    'ValidationTrialCount',fit.ReferenceHeldout.TrialCount, ...
    'ValidationErrorCount',fit.ReferenceHeldout.ErrorCount, ...
    'SupportedMask',fit.Reference.SupportedMask, ...
    'CountPopulation',"independent_awgn_reference_not_target_fading_crc", ...
    'ReferencePhysicalKey',spec.ReferenceKey, ...
    'ReferenceCollectionIdentity',fit.ReferenceCollectionIdentity, ...
    'TargetCollectionIdentity',fit.TargetCollectionIdentity, ...
    'SourceIdentitySHA256',fit.SourceIdentitySHA256, ...
    'FadingValidationGroups',fit.ValidationGroups, ...
    'SourceClassification',"waveform_reference_with_held_out_fading_eesm_validation");
sixgr.system.abstraction.validateBLERCurve(curve,policy);
end

function folder=localFolder(root,relative,digest)
relative=string(relative); digest=string(digest);
assert(isscalar(relative) && strlength(relative)>0 && ...
    ~java.io.File(char(relative)).isAbsolute() && isscalar(digest) && strlength(digest)==64, ...
    'sixgr:abstraction:GrantCalibrationSource','Require a relative retained collection and manifest hash.');
base=string(java.io.File(char(root)).getCanonicalPath());
folder=string(java.io.File(char(fullfile(root,relative))).getCanonicalPath());
assert(startsWith(folder,base+string(filesep)), ...
    'sixgr:abstraction:GrantCalibrationSource','Collection escapes the retained package root.');
manifest=fullfile(folder,'campaign.mat');
assert(~isfile(fullfile(folder,'source_change_failure.json')), ...
    'sixgr:calibration:GrantSourceChanged', ...
    'A collection with a recorded mid-execution source change cannot be installed.');
sixgr.calibration.verifyEpisodeFile(manifest);
assert(strcmpi(sixgr.csi.studyFileSHA256(manifest),digest), ...
    'sixgr:abstraction:CalibrationDigest','Collection manifest differs from its frozen package binding.');
retained=load(manifest,'sources');
assert(isfield(retained,'sources'),'sixgr:abstraction:GrantCalibrationSource', ...
    'Retained collection has no source/environment identity.');
sixgr.calibration.assertGrantSourceIdentity(retained.sources);
end
