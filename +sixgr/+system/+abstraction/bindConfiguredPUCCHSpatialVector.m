function [bound,binding]=bindConfiguredPUCCHSpatialVector(cfg,assignment)
% Bind the installed active PUCCH relation to an explicit UE antenna vector.
% No SVD/identity fallback and no substitution of a PUSCH rank precoder.
assert(isa(assignment,'sixgr.phy.pucch.PUCCHTransmissionAssignment'), ...
    'sixgr:abstraction:PUCCHEmissionSpatialBinding','Require the materialized PUCCH assignment.');
catalog=sixgr.util.structGet(cfg,'system.linkAbstraction.dynamicPUCCH.spatialVectorCatalog',[]);
assert(isstruct(catalog) && ~isempty(catalog) && all(isfield(catalog, ...
    {'SpatialRelationID','ReferenceSignalType','ReferenceSignalID','BeamID','ConfigurationEpoch', ...
    'PrecoderReal','PrecoderImag'})), ...
    'sixgr:abstraction:PUCCHEmissionSpatialBinding','Configure the active relation-to-UE-vector catalog in YAML.');
s=assignment.SpatialRelationState.Data;
ids=[catalog.SpatialRelationID];
assert(isnumeric(ids) && all(isfinite(ids) & ids>=0 & ids==fix(ids)) && ...
    numel(unique(ids))==numel(ids),'sixgr:abstraction:PUCCHEmissionSpatialBinding', ...
    'Every installed spatial relation must have one unique nonnegative identity.');
index=find(ids==s.ActiveSpatialRelationID);
assert(isscalar(index),'sixgr:abstraction:PUCCHEmissionSpatialBinding', ...
    'No antenna vector is installed for the active spatial relation.');
entry=catalog(index);
assert(entry.ConfigurationEpoch==assignment.ConfigurationEpoch && ...
    entry.SpatialRelationID==s.SpatialRelationID && entry.BeamID==s.SelectedBeamID && ...
    entry.BeamID==s.AppliedBeamID && entry.ReferenceSignalID==s.ReferenceSignalID && ...
    strcmpi(string(entry.ReferenceSignalType),string(s.ReferenceSignalType)), ...
    'sixgr:abstraction:PUCCHEmissionSpatialBinding', ...
    'Configured vector must match the activated reference, beam and configuration epoch.');
validateattributes([s.StateAgeSlots s.MaximumAgeSlots],{'numeric'}, ...
    {'vector','numel',2,'integer','nonnegative','finite'});
assert(s.StateAgeSlots<=s.MaximumAgeSlots,'sixgr:abstraction:PUCCHEmissionSpatialBinding', ...
    'Expired spatial state cannot select a configured vector.');
re=entry.PrecoderReal; im=entry.PrecoderImag;
ports=cfg.system.linkAbstraction.networkSpatial.uePorts;
assert(isnumeric(re) && isnumeric(im) && isreal(re) && isreal(im) && ...
    isvector(re) && isvector(im) && numel(re)==ports && numel(im)==ports && ...
    all(isfinite(re)) && all(isfinite(im)), ...
    'sixgr:abstraction:PUCCHEmissionSpatialBinding','Provide one complex coefficient per physical UE transmit dimension.');
W=complex(double(re(:)),double(im(:)));
assert(abs(sum(abs(W).^2)-1)<1e-12, ...
    'sixgr:abstraction:PUCCHEmissionSpatialBinding','Configured vector must already be unit norm; no hidden renormalization.');
matrixDigest=string(sixgr.phy.mimo.MatrixContract.digest(W));
configurationDigest=string(sixgr.util.sha256Hex(uint8(unicode2native( ...
    jsonencode(sixgr.util.jsonSafeValue(entry)),'UTF-8'))));
if isfield(s,'PhysicalPrecoderSHA256')
    assert(string(s.PhysicalPrecoderSHA256)==matrixDigest && ...
        isfield(s,'PhysicalPrecoderConfigurationSHA256') && ...
        string(s.PhysicalPrecoderConfigurationSHA256)==configurationDigest, ...
        'sixgr:abstraction:PUCCHEmissionSpatialBinding','An already bound spatial state cannot acquire a different vector/configuration.');
    bound=assignment;
    binding=struct('Precoder',W,'SpatialStateDigest',assignment.SpatialRelationState.Digest);
    return;
end
s.ParentSpatialStateDigest=assignment.SpatialRelationState.Digest;
s.PhysicalPrecoderSHA256=matrixDigest;
s.PhysicalPrecoderSource="yaml.system.linkAbstraction.dynamicPUCCH.spatialVectorCatalog";
s.PhysicalPrecoderConfigurationSHA256=configurationDigest;
spatial=sixgr.phy.pucch.PUCCHSpatialRelationState(s);
bound=sixgr.phy.pucch.PUCCHTransmissionAssignment(assignment.Data, ...
    assignment.Resource,assignment.PowerControlState,spatial);
binding=struct('Precoder',W,'SpatialStateDigest',spatial.Digest);
end
