function emissions=buildScheduledCSIRSEmissions(cfg,state)
% Actual native CSI-RS port samples, not a calendar/reservation surrogate.
% This is an explicit ideal-RF SLS model: equal aggregate antenna-domain
% power per occupied RE, with native CDM and a frozen configured beam basis.
% It does not claim a noisy UE estimator or accepted physical calibration.
emissions=struct([]);
p=cfg.system.linkAbstraction.networkSpatial;
assert(string(p.csirsPowerPolicy)=="configured_bs_full_carrier_psd_per_occupied_re" && ...
    string(p.csirsPhaseAssumption)=="native_sequence_phase_at_committed_epoch", ...
    'sixgr:abstraction:CSIRSEmissionPolicy','Declare CSI-RS power and relative-phase assumptions.');
assert(isfield(state,'AbsoluteSlot0') && state.AbsoluteSlot0==state.TTI-1, ...
    'sixgr:abstraction:CSIRSEmissionIdentity','CSI-RS must bind the committed absolute slot.');
if ~logical(sixgr.util.structGet(cfg,'phy.csirs.enable',false)), return; end
slot=state.AbsoluteSlot0;
[due,~]=sixgr.phy.refsig.csirsOccasion(cfg,slot);
if ~due, return; end
power=double(state.LargeScaleState.TxPower_dBm);
assert(~isempty(power) && all(isfinite(power),'all') && ...
    all(abs(power-power(1,:))<1e-12,'all'), ...
    'sixgr:abstraction:CSIRSEmissionPower', ...
    'Cell-common CSI-RS requires one transmitter power per cell, not UE-dependent BS powers.');
ids=double(p.csirsScramblingIDs(:)); nc=size(power,2);
assert(numel(ids)==nc && all(isfinite(ids) & ids==fix(ids) & ids>=0 & ids<=1023), ...
    'sixgr:abstraction:CSIRSEmissionIdentity','Configure one explicit CSI-RS scrambling NID (0..1023) per cell.');
B=complex(sixgr.util.structGet(cfg,'phy.csirs.precoderMatrices',[]));
assert(~isempty(B) && size(B,1)==p.bsPorts, ...
    'sixgr:abstraction:CSIRSEmissionBasis','Native emitted CSI-RS requires the configured physical beam matrices.');
resources=double(sixgr.util.structGet(cfg,'phy.csirs.resourceIDs',[]));
if isempty(resources), resources=double(sixgr.util.structGet(cfg,'phy.csirs.resourceID',NaN)); end
assert(numel(resources)==size(B,3) && all(isfinite(resources) & resources==fix(resources) & resources>=0), ...
    'sixgr:abstraction:CSIRSEmissionIdentity','Each transmitted beam must have an explicit configured resource ID.');
carrier=nrCarrierConfig('NSizeGrid',cfg.phy.carrier.NSizeGrid, ...
    'NStartGrid',cfg.phy.carrier.NStartGrid,'SubcarrierSpacing',cfg.phy.carrier.SubcarrierSpacing, ...
    'NCellID',cfg.phy.carrier.NCellID);
carrier.NSlot=mod(slot,carrier.SlotsPerFrame);
% CSI sequence slot identity uses the native radio-frame clock. Preserve the
% full frame here, as the shared generator asserts its absolute-slot binding.
carrier.NFrame=floor(slot/carrier.SlotsPerFrame);
K=12*carrier.NSizeGrid; L=carrier.SymbolsPerSlot; nt=p.bsPorts;
localCfg=cfg; localCfg.lls6g.runtime.AbsoluteSlotIndex0=slot;
for cellID=1:nc
    localCfg.phy.csirs.scramblingID=ids(cellID);
    material=sixgr.phy.refsig.materializeCSIRSPhysicalGrid(carrier,localCfg, ...
        'WaveformPortCount',nt,'OwnershipMode','emit');
    assert(material.Event.Transmitted,'sixgr:abstraction:CSIRSEmissionConfig', ...
        'A due CSI-RS occasion must have native emitted samples.');
    watts=10^((power(1,cellID)-30)/10);
    for ri=1:numel(material.Event.ResourceEvents)
        resource=material.Event.ResourceEvents(ri);
        grid=complex(zeros(K,L,nt));
        grid(resource.WaveformIndices)=resource.WaveformSymbols;
        flat=reshape(grid,K*L,nt); occupied=find(any(flat~=0,2));
        [k,l]=ind2sub([K L],occupied); coords=[k-1 l-1];
        symbols=double(flat(occupied,:)); energy=sum(abs(symbols).^2,2);
        assert(~isempty(energy) && all(energy>0) && ...
            max(abs(energy-energy(1)))<=1e-10*energy(1), ...
            'sixgr:abstraction:CSIRSEmissionPower', ...
            'The declared flat EPRE model requires constant native occupied-RE energy; do not reshape CDM amplitudes.');
        part=sixgr.util.resolveTDDSlotPartition(cfg,slot); a=part.DLSymbolAllocation;
        assert(all(coords(:,2)>=a(1) & coords(:,2)<sum(a)), ...
            'sixgr:abstraction:CSIRSEmissionTiming','Actual CSI-RS must fit resolved DL symbols.');
        % Shared data has the same full-carrier PSD. It must exclude CSI-RS
        % REs, otherwise adding this emitter would double-count BS power.
        assert(numel(state.GrantsDL)==numel(state.GrantCellsDL), ...
            'sixgr:abstraction:CSIRSEmissionIdentity','Every DL grant needs its transmitter identity.');
        for j=1:numel(state.GrantsDL)
            if state.GrantCellsDL(j)~=cellID, continue; end
            map=sixgr.system.abstraction.scheduledDataREMap(cfg,state.GrantsDL(j),slot);
            assert(~any(ismember(coords,map.Coordinates0Based,'rows')), ...
                'sixgr:abstraction:CSIRSEmissionDataCollision', ...
                'The executed DL data map must exclude its cell-common CSI-RS REs.');
        end
        % Symbols already contain the executed physical beam. The unit-
        % Frobenius identity below only adapts the finite operator interface;
        % sqrt(nt) compensates it exactly (no extra antenna-count gain).
        row=struct('SourceTTI',state.TTI,'AbsoluteSlot0',slot,'ServingCellID',cellID, ...
            'ResourceID',resource.ResourceID,'CRI',ri-1,'ScramblingID',ids(cellID), ...
            'Signal',"CSI-RS",'Coordinates0Based',coords,'Symbols',symbols*sqrt(nt), ...
            'Precoder',eye(nt)/sqrt(nt), ...
            'TransmitPowerPerRE_W',repmat(watts/K/energy(1),numel(energy),1), ...
            'ConfiguredTotalPower_W',watts,'AggregateAntennaEPRE_W',watts/K, ...
            'PhysicalPrecoderSHA256',string(resource.WaveformPrecoderDigest), ...
            'SymbolSource',"materializeCSIRSPhysicalGrid_nrCSIRS_and_nrCSIRSIndices", ...
            'PhaseAssumption',string(p.csirsPhaseAssumption),'PowerPolicy',string(p.csirsPowerPolicy));
        row.SHA256=string(sixgr.util.sha256Hex(uint8(unicode2native( ...
            jsonencode(sixgr.util.jsonSafeValue(row)),'UTF-8'))));
        emissions=[emissions row]; %#ok<AGROW>
    end
end
end
