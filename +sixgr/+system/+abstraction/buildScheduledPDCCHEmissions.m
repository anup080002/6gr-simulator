function emissions=buildScheduledPDCCHEmissions(cfg,state,csirs,ssb)
% Native coded DCI/DM-RS on issued control occasions, not data occasions.
% Symbol generation is physical; propagation/control delivery remain labeled
% SLS assumptions. Fixed configured cell beams are NOT dynamic TCI tracking.
if nargin<3, csirs=struct([]); end
if nargin<4, ssb=struct([]); end
emissions=struct([]); p=cfg.system.linkAbstraction.networkSpatial;
required={'IssuedGrantsDL','IssuedGrantCellsDL','IssuedGrantsUL','IssuedGrantCellsUL'};
assert(all(isfield(state,required)), 'sixgr:abstraction:PDCCHIssuedPopulation', ...
    'Commit explicit issued-control populations, including empty occasions; never infer DCI from executing data.');
state=sixgr.system.bindSLSIssuedControlPopulation(state,state.IssuedGrantsDL, ...
    state.IssuedGrantCellsDL,state.IssuedGrantsUL,state.IssuedGrantCellsUL);
assert(string(p.pdcchPowerPolicy)=="configured_bs_full_carrier_psd_per_occupied_re" && ...
    string(p.pdcchPhaseAssumption)=="native_sequence_phase_at_committed_epoch" && ...
    string(p.pdcchBeamPolicy)=="configured_fixed_cell_beam", ...
    'sixgr:abstraction:PDCCHEmissionPolicy','Declare PDCCH power, relative phase and fixed-cell beam assumptions.');
power=double(state.LargeScaleState.TxPower_dBm); nc=size(power,2);
assert(~isempty(power) && all(isfinite(power),'all') && ...
    all(abs(power-power(1,:))<1e-12,'all'), ...
    'sixgr:abstraction:PDCCHEmissionPower','Require one configured BS power per cell, not UE-dependent BS transmit powers.');
ids=double(p.pdcchScramblingIDs(:)); beams=double(p.pdcchPrecoderMatrices);
assert(numel(ids)==nc && all(isfinite(ids) & ids>=0 & ids<=65535 & ids==fix(ids)) && ...
    isequal(size(beams),[p.bsPorts nc]) && all(isfinite(beams),'all') && ...
    all(abs(sum(abs(beams).^2,1)-1)<1e-12), ...
    'sixgr:abstraction:PDCCHEmissionBasis','Supply one scrambling ID and unit-norm physical beam column per cell.');
carrier=sixgr.phy.grid.makeCarrier(cfg); slot=state.AbsoluteSlot0;
carrier.NSlot=mod(slot,carrier.SlotsPerFrame);
carrier.NFrame=mod(floor(slot/carrier.SlotsPerFrame),1024);
K=12*carrier.NSizeGrid; L=carrier.SymbolsPerSlot;
reserved=cell(1,nc); [reserved{:}]=deal(zeros(0,2));
for e=csirs
    assert(e.AbsoluteSlot0==slot && e.ServingCellID>=1 && e.ServingCellID<=nc, ...
        'sixgr:abstraction:PDCCHEmissionIdentity','CSI-RS exclusions must belong to this cell/slot.');
    reserved{e.ServingCellID}=[reserved{e.ServingCellID}; ...
        e.Coordinates0Based+[12*carrier.NStartGrid 0]];
end
for e=ssb
    assert(e.AbsoluteSlot0==slot && e.ServingCellID>=1 && e.ServingCellID<=nc, ...
        'sixgr:abstraction:PDCCHEmissionIdentity','SSB exclusions must belong to this cell/slot.');
    reserved{e.ServingCellID}=[reserved{e.ServingCellID}; ...
        e.ReservedCoordinates0Based+[12*carrier.NStartGrid 0]];
end
for direction=["DL","UL"]
    grants=state.("IssuedGrants"+direction); cells=state.("IssuedGrantCells"+direction);
    for j=1:numel(grants)
        g=grants(j); c=cells(j);
        assert(c<=nc && isfield(g,'DCI') && isstruct(g.DCI) && ...
            isfield(g.DCI,'Bits') && ~isempty(g.DCI.Bits) && ...
            (isnumeric(g.DCI.Bits)||islogical(g.DCI.Bits)) && ...
            isvector(g.DCI.Bits) && all(g.DCI.Bits(:)==0|g.DCI.Bits(:)==1), ...
            'sixgr:abstraction:PDCCHEmissionPayload','Issued DCI must contain actual authored binary payload bits; no zero/random fallback.');
        local=cfg; local.phy.pdsch.RNTI=g.RNTI; local.phy.pusch.RNTI=g.RNTI;
        local.phy.pdcch.rnti=g.RNTI;
        local.lls6g.runtime.AbsoluteSlotIndex0=slot;
        control=sixgr.util.structGet(local,'phy.pdcch.operatorControl',struct());
        assert(~isfield(control,'coreset_qcl_association') || isempty(control.coreset_qcl_association), ...
            'sixgr:abstraction:PDCCHEmissionTCI', ...
            'Fixed-cell beam emission cannot override an installed CORESET QCL/TCI association; integrate its physical beam first.');
        if isfield(control,'connected_dci')
            local.phy.pdcch.operatorControl.connected_monitoring.dmrs_scrambling_id=ids(c);
        elseif isfield(control,'pdcch_strict')
            local.phy.pdcch.operatorControl.pdcch_strict.rnti.value=g.RNTI;
        end
        local.phy.pdcch.dmrsScramblingID=ids(c);
        level=sixgr.util.structGet(g,'PDCCHAggregationLevel',local.phy.pdcch.aggregationLevel);
        assert(isnumeric(level) && isreal(level) && isscalar(level) && ...
            ismember(level,[1 2 4 8 16]), ...
            'sixgr:abstraction:PDCCHEmissionAggregation','Do not replace an invalid issued/configured aggregation level with a default.');
        [tx,info]=sixgr.phy.dl.PDCCH_Tx(local,'Carrier',carrier,'Grant',g, ...
            'RNTI',g.RNTI,'PDCCHScramblingRNTI',g.RNTI, ...
            'NCellID',ids(c),'NumTxAnt',1,'OFDMModulate',false, ...
            'ReservedRECoordinates',reserved{c});
        assert(~info.RandomDCIPayload && ...
            string(info.DCIPayloadSource)=="finalized_scheduler_grant_dci_bits" && ...
            isequal(double(tx.DCIBits(:)),double(g.DCI.Bits(:))) && ...
            tx.PDCCH.DMRSScramblingID==ids(c) && info.PDCCHScramblingID==ids(c) && ...
            tx.PDCCH.AggregationLevel==level && tx.PDCCH.RNTI==g.RNTI, ...
            'sixgr:abstraction:PDCCHEmissionIdentity', ...
            'Native transmitter must preserve issued bits, aggregation level and installed scrambling/RNTI identity.');
        flat=reshape(tx.Grid,K*L,1); occupied=find(flat~=0);
        [k,l]=ind2sub([K L],occupied); coords=[k-1 l-1]; symbols=double(flat(occupied));
        assert(~isempty(symbols) && all(abs(abs(symbols).^2-1)<1e-12), ...
            'sixgr:abstraction:PDCCHEmissionPower', ...
            'Declared unit-EPRE coding requires unit-power native PDCCH/DM-RS symbols.');
        part=sixgr.util.resolveTDDSlotPartition(cfg,slot); a=part.DLSymbolAllocation;
        assert(all(coords(:,2)>=a(1) & coords(:,2)<sum(a)), ...
            'sixgr:abstraction:PDCCHEmissionTiming','Issued PDCCH must occupy legal DL symbols.');
        % Do not silently add control on top of an already-issued PDSCH RE.
        % Native PDCCH candidate selection handles earlier control/CSI-RS.
        for k=1:numel(state.GrantsDL)
            if state.GrantCellsDL(k)~=c, continue; end
            [map,dataCarrier,pdsch]=sixgr.system.abstraction.scheduledDataREMap(cfg,state.GrantsDL(k),slot);
            dmrs=nrPDSCHDMRSIndices(dataCarrier,pdsch); ptrs=nrPDSCHPTRSIndices(dataCarrier,pdsch);
            pilot=double([dmrs(:);ptrs(:)])-1;
            pilotCoords=[mod(pilot(:),K),mod(floor(pilot(:)/K),L)];
            occupiedData=unique([map.Coordinates0Based;pilotCoords],'rows');
            assert(~any(ismember(coords,occupiedData,'rows')), ...
                'sixgr:abstraction:PDCCHDataCollision','Executed PDSCH data/DM-RS/PT-RS must exclude its cell PDCCH resources.');
        end
        reserved{c}=[reserved{c};info.AllocatedRECoordinates];
        watts=10^((power(1,c)-30)/10);
        row=struct('SourceTTI',state.TTI,'AbsoluteSlot0',slot,'ServingCellID',c, ...
            'UEIndex',sixgr.system.resolveGrantUEIndex(g),'RNTI',g.RNTI, ...
            'ScheduledDirection',direction,'ScheduledAbsoluteSlot0',g.ScheduledAbsoluteSlot, ...
            'Signal',"PDCCH_and_DMRS",'ScramblingID',ids(c), ...
            'Coordinates0Based',coords,'Symbols',symbols,'Precoder',beams(:,c), ...
            'TransmitPowerPerRE_W',repmat(watts/K,numel(occupied),1), ...
            'ConfiguredTotalPower_W',watts,'AggregateAntennaEPRE_W',watts/K, ...
            'AggregationLevel',tx.PDCCH.AggregationLevel,'Candidate',tx.PDCCH.AllocatedCandidate, ...
            'DCIBits',tx.DCIBits,'DCICodeword',tx.DCICW, ...
            'DCIPayloadSHA256',string(sixgr.phy.mimo.MatrixContract.digest(tx.DCIBits)), ...
            'PhysicalPrecoderSHA256',string(sixgr.phy.mimo.MatrixContract.digest(beams(:,c))), ...
            'SymbolSource',"PDCCH_Tx_nrDCIEncode_nrPDCCH_nrPDCCHResources", ...
            'PhaseAssumption',string(p.pdcchPhaseAssumption),'PowerPolicy',string(p.pdcchPowerPolicy), ...
            'BeamPolicy',string(p.pdcchBeamPolicy),'ControlReceptionQualified',false);
        row.SHA256=string(sixgr.util.sha256Hex(uint8(unicode2native( ...
            jsonencode(sixgr.util.jsonSafeValue(row)),'UTF-8'))));
        emissions=[emissions row]; %#ok<AGROW>
    end
end
end
