function indicator=singleSRSResourceIndicator(strict)
% DCI SRI indexes the configured resource set; it is not srs-ResourceId.
% The current native SLS producer executes one resource per UE/occasion.
% Multiple resources need explicit population generation and selection;
% taking the first entry is not a supported multi-resource procedure.
assert(isstruct(strict) && isscalar(strict) && ...
    all(isfield(strict,{'ResourceIds','ResourceId','NumResources'})), ...
    'sixgr:abstraction:SRSResourceSetIdentity','Retain the installed SRS resource set.');
ids=double(strict.ResourceIds);
assert(isscalar(ids) && isfinite(ids) && ids>=0 && ids==fix(ids) && ...
    isequal(double(strict.NumResources),1) && isequal(double(strict.ResourceId),ids), ...
    'sixgr:abstraction:SRSMultipleResourcesUnsupported', ...
    'This SLS producer supports one installed SRS resource per UE; do not silently select the first of several.');
indicator=0;
end
