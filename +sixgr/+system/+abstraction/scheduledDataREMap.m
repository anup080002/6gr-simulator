function [map,carrier,channel] = scheduledDataREMap(cfg,grant,absoluteSlot0)
%SCHEDULEDDATAREMAP Resolve native resources from an actual frozen SLS grant.
% This allocation plan is not a decoded waveform or qualified calibration.
arguments
    cfg (1,1) struct
    grant (1,1) struct
    absoluteSlot0 (1,1) double {mustBeInteger,mustBeNonnegative,mustBeFinite}
end
assert(all(isfield(grant,{'PHYGrant','Direction','RNTI','PRBSet', ...
    'SymbolAllocation','NumLayers','ScheduledAbsoluteSlot'})) && ...
    isequal(sixgr.util.structGet(grant,'PHYGrant.IsFrozen',false),true), ...
    'sixgr:abstraction:DataREGrant','Require an issued frozen grant, not a rectangular resource fixture.');
frozen=grant.PHYGrant;
sixgr.phy.grant.assertPHYGrantDimensions(frozen,'sls_data_re_mapping');
sixgr.phy.grant.assertGrantTimingIdentity(grant,grant.Direction);
assert(grant.ScheduledAbsoluteSlot==absoluteSlot0 && ...
    string(grant.Direction)==string(frozen.Direction) && ...
    grant.RNTI==frozen.ChannelStateKey.RNTI && ...
    isequal(double(grant.PRBSet(:)),double(frozen.ResourceAllocation.PRBSet(:))) && ...
    isequal(double(grant.SymbolAllocation(:)),double(frozen.ResourceAllocation.SymbolAllocation(:))) && ...
    grant.NumLayers==frozen.AntennaArchitecture.NumLayers, ...
    'sixgr:abstraction:DataREGrantIdentity','Mutable grant fields differ from their frozen resource or execution clock.');
replay=sixgr.phy.grant.applyPHYGrantToConfig(cfg,frozen);
carrier=sixgr.phy.grid.makeCarrier(replay);
carrier.NSlot=mod(absoluteSlot0,carrier.SlotsPerFrame);
carrier.NFrame=mod(floor(absoluteSlot0/carrier.SlotsPerFrame),1024);
if string(grant.Direction)=="DL"
    [~,~,channel]=sixgr.phy.grid.allocREsPDSCH(carrier,replay,'RNTI',grant.RNTI);
else
    [~,~,channel,experimental]=sixgr.phy.grid.allocPUSCHTransport(carrier,replay,'RNTI',grant.RNTI);
    assert(isempty(experimental),'sixgr:abstraction:DataREExperimentalTransport', ...
        'Native geometry alone cannot prove an experimental coded-bit population.');
end
map=sixgr.phy.resource.sharedDataREMap(carrier,channel);
% Use actual resolved indices in the calibration identity. Two grants with
% the same PRB rectangle but different DM-RS, PT-RS or reservations cannot
% silently select the same resource-population calibration.
identity=struct('Schema',"sixgr.scheduled_data_re_identity/v1", ...
    'ResourcePopulation',map.ResourcePopulation, ...
    'CoordinatesSHA256',string(sixgr.phy.mimo.MatrixContract.digest(map.Coordinates0Based)), ...
    'NumLayers',map.NumLayers,'NativeIndexPlaneCount',map.NativeIndexPlaneCount, ...
    'PhysicalRECount',map.PhysicalRECount,'CodedBitsPerCodeword',map.CodedBitsPerCodeword, ...
    'NSizeGrid',double(carrier.NSizeGrid),'NStartGrid',double(carrier.NStartGrid), ...
    'SubcarrierSpacing',double(carrier.SubcarrierSpacing),'CyclicPrefix',string(carrier.CyclicPrefix));
map.AllocationIdentity=identity;
map.AllocationIdentitySHA256=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(identity),'UTF-8'))));
map.ScheduledAbsoluteSlot0=absoluteSlot0;
map.GrantContextId=string(frozen.GrantContextId);
end
