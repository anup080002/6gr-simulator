function emissions=validateCommittedPUCCHEmissions(cfg,state,srs)
% A reservation is not a native transmitter population. Validate before commit.
assert(all(isfield(state,{'PUCCHEmissions','AbsoluteSlot0','ServingCells','RNTIByUE'})) && ...
    isstruct(state.PUCCHEmissions),'sixgr:abstraction:PUCCHEmissionPopulation', ...
    'Commit an explicit native PUCCH population, including empty occasions; missing is not silence.');
emissions=state.PUCCHEmissions;
p=cfg.system.linkAbstraction.networkSpatial;
part=sixgr.util.resolveTDDSlotPartition(cfg,state.AbsoluteSlot0); a=part.ULSymbolAllocation;
carrier=sixgr.phy.grid.makeCarrier(cfg); L=carrier.SymbolsPerSlot; K=12*carrier.NSizeGrid;
allowed="modeled_SLS_ideal_delayed_control";
if logical(cfg.system.linkAbstraction.allowDevelopmentFixtures)
    allowed=[allowed "declared_component_fixture_not_study_result"];
end
for n=1:numel(emissions)
    e=emissions(n);
    fields={'SHA256','SourceTTI','AbsoluteSlot0','UEIndex','ServingCellID','RNTI', ...
        'Coordinates0Based','Symbols','Precoder','TransmitPowerPerRE_W','AppliedTotalPower_W', ...
        'NativeWaveformExecuted','PhysicalReceptionQualified','RFImpairmentsApplied', ...
        'ElementPatternsApplied','Signal','SourceClassification','PowerPolicy','PhaseAssumption', ...
        'SpatialEvidence','SpatialStateDigest','PowerControlEvidence','ObligationID','ObligationSHA256'};
    assert(all(isfield(e,fields)),'sixgr:abstraction:PUCCHEmissionPopulation', ...
        'Require the complete native transmitter adapter evidence.');
    actual=string(sixgr.util.sha256Hex(uint8(unicode2native( ...
        jsonencode(sixgr.util.jsonSafeValue(rmfield(e,'SHA256'))),'UTF-8'))));
    assert(isscalar(string(e.SHA256)) && string(e.SHA256)==actual, ...
        'sixgr:abstraction:PUCCHEmissionMutation','Generated PUCCH payload, phase, power or identity changed.');
    u=e.UEIndex;
    assert(isscalar(u) && isfinite(u) && u==fix(u) && u>=1 && u<=numel(state.ServingCells) && ...
        u<=numel(state.RNTIByUE) && e.SourceTTI==state.TTI && e.AbsoluteSlot0==state.AbsoluteSlot0 && ...
        e.ServingCellID==state.ServingCells(u) && e.RNTI==state.RNTIByUE(u), ...
        'sixgr:abstraction:PUCCHEmissionIdentity','Emit only for the actual committed UE/cell/slot.');
    assert(isequal(e.NativeWaveformExecuted,true) && isequal(e.PhysicalReceptionQualified,false) && ...
        isequal(e.RFImpairmentsApplied,false) && isequal(e.ElementPatternsApplied,false) && ...
        e.Signal=="PUCCH" && any(e.SourceClassification==allowed) && ...
        e.PowerPolicy==string(p.pucchPowerPolicy) && e.PhaseAssumption==string(p.pucchPhaseAssumption), ...
        'sixgr:abstraction:PUCCHEmissionSource','Native ideal-RF symbols retain modeled/fixture control provenance.');
    coords=e.Coordinates0Based; W=e.Precoder; q=e.TransmitPowerPerRE_W;
    assert(isnumeric(coords) && size(coords,2)==2 && ~isempty(coords) && all(isfinite(coords),'all') && ...
        all(coords==fix(coords),'all') && all(coords(:,1)>=0 & coords(:,1)<K) && ...
        all(coords(:,2)>=0 & coords(:,2)<L & coords(:,2)>=a(1) & coords(:,2)<sum(a)) && ...
        size(unique(coords,'rows'),1)==size(coords,1) && ...
        isequal(size(W),[p.uePorts 1]) && all(isfinite(W),'all') && abs(norm(W)^2-1)<1e-12 && ...
        isequal(size(e.Symbols),[size(coords,1) 1]) && all(isfinite(e.Symbols),'all') && ...
        isequal(size(q),[size(coords,1) 1]) && all(isfinite(q) & q>0), ...
        'sixgr:abstraction:PUCCHEmissionResource','Native PUCCH needs legal UL REs, dimensions and finite power.');
    spatial=sixgr.phy.pucch.PUCCHSpatialRelationState(e.SpatialEvidence);
    assert(string(e.SpatialStateDigest)==spatial.Digest && ...
        isfield(spatial.Data,'PhysicalPrecoderSHA256') && ...
        string(spatial.Data.PhysicalPrecoderSHA256)==string(sixgr.phy.mimo.MatrixContract.digest(W)), ...
        'sixgr:abstraction:PUCCHEmissionSpatialBinding','Committed antenna samples must retain their typed spatial-vector binding.');
    power=sixgr.phy.pucch.PUCCHPowerControlState(e.PowerControlEvidence);
    resolved=sixgr.phy.pucch.PUCCHPowerController.resolve(power);
    assert(isfinite(resolved.AppliedPowerdBm) && ...
        abs(10^((resolved.AppliedPowerdBm-30)/10)-e.AppliedTotalPower_W)<=1e-12*e.AppliedTotalPower_W, ...
        'sixgr:abstraction:PUCCHEmissionPower','Committed watts must come from the retained typed power state.');
    if e.SourceClassification=="modeled_SLS_ideal_delayed_control"
        assert(isfield(power.Data,'ModeledReference') && ~resolved.RuntimeMeasuredPathlossUsed, ...
            'sixgr:abstraction:PUCCHEmissionPower','Modeled SLS requires its causal reference, not a relabeled physical measurement.');
        ref=power.Data.ModeledReference;
        assert(ref.Available && ref.KnownAtAbsoluteSlot0==state.AbsoluteSlot0 && ...
            ref.UEIndex==u && ref.RNTI==e.RNTI && ref.ServingCell==e.ServingCellID && ...
            ref.ReferenceAvailableAtSlot0<=state.AbsoluteSlot0 && ref.CapturedAtAbsoluteSlot0<state.AbsoluteSlot0 && ...
            ~ref.WaveformMeasured && ref.PathlossdB==power.Data.PathlossdB, ...
            'sixgr:abstraction:PUCCHEmissionPower','Power-reference identity and causal clock must survive commit.');
    end
    % This implementation does not yet share a UE's instantaneous power
    % across simultaneous PUCCH/PUSCH/SRS or multiple PUCCHs. Do not silently
    % execute each at a full independent power budget, even on disjoint PRBs.
    for g=reshape(state.GrantsUL,1,[])
        if sixgr.system.resolveGrantUEIndex(g)~=u, continue; end
        assert(~any(coords(:,2)>=g.SymbolAllocation(1) & coords(:,2)<sum(g.SymbolAllocation)), ...
            'sixgr:abstraction:PUCCHSimultaneousPowerUnsupported','Same-UE PUCCH/PUSCH needs explicit multiplexing/power sharing.');
    end
    for j=1:numel(srs)+n-1
        if j<=numel(srs), other=srs(j); else, other=emissions(j-numel(srs)); end
        assert(other.UEIndex~=u || ~any(ismember(coords(:,2),other.Coordinates0Based(:,2))), ...
            'sixgr:abstraction:PUCCHSimultaneousPowerUnsupported','Overlapping same-UE emissions require an explicit joint power procedure.');
    end
end
localValidateCoverage(cfg,state,emissions);
end
function localValidateCoverage(cfg,state,emissions)
% Only explicitly declared isolated emission fixtures may omit a MAC ledger.
fixtureOnly=logical(cfg.system.linkAbstraction.allowDevelopmentFixtures) && ...
    (isempty(emissions) || all(string({emissions.SourceClassification})=="declared_component_fixture_not_study_result"));
if fixtureOnly && ~isfield(state,'UCIEmissionObligations') && ~isfield(state,'PUCCHEmissionAudit'), return; end
assert(all(isfield(state,{'UCIEmissionObligations','PUCCHEmissionAudit'})) && ...
    isstruct(state.UCIEmissionObligations) && istable(state.PUCCHEmissionAudit), ...
    'sixgr:abstraction:PUCCHEmissionCoverage','Require one disposition for every current owned UCI obligation.');
due=state.UCIEmissionObligations; a=state.PUCCHEmissionAudit;
assert(height(a)==numel(due),'sixgr:abstraction:PUCCHEmissionCoverage','A reservation/obligation cannot silently disappear.');
if isempty(due)
    assert(isempty(emissions),'sixgr:abstraction:PUCCHEmissionCoverage','No owned obligation exists for these emitted symbols.');
    return;
end
required={'ObligationID','AbsoluteSlot0','UEIndex','RNTI','CellID','Transport', ...
    'HARQBits','SRBits','CSIPart1Bits','CSIPart2Bits','Disposition','NativeWaveformExecuted', ...
    'EmissionSHA256','ReplacementPUSCHGrantSHA256','PhysicalReceptionQualified','SourceClassification', ...
    'SRPayloadKnown','PositiveSRCount'};
assert(all(ismember(required,a.Properties.VariableNames)) && ...
    numel(unique(a.ObligationID))==height(a) && numel(unique(string({due.ResourceID})))==numel(due), ...
    'sixgr:abstraction:PUCCHEmissionCoverage','Native population audit needs unique complete obligation identities.');
for k=1:numel(due)
    o=due(k); row=a(a.ObligationID==string(o.ResourceID),:);
    assert(height(row)==1 && row.AbsoluteSlot0==state.AbsoluteSlot0 && o.AbsoluteSlot0==state.AbsoluteSlot0 && ...
        row.UEIndex==o.UEIndex && row.RNTI==o.RNTI && row.CellID==o.CellID && ...
        row.Transport==string(o.Transport) && row.HARQBits==o.HARQBits && row.SRBits==o.SRBits && ...
        row.CSIPart1Bits==o.CSIPart1Bits && row.CSIPart2Bits==o.CSIPart2Bits && ...
        ~row.PhysicalReceptionQualified && row.SourceClassification=="modeled_SLS_ideal_delayed_control", ...
        'sixgr:abstraction:PUCCHEmissionCoverage','Audit must retain the independent obligation, not reconstruct it from transmitted bits.');
    if row.Transport=="PUCCH" && row.SRBits>0
        assert(row.SRPayloadKnown && any(row.PositiveSRCount==[0 1]), ...
            'sixgr:abstraction:PUCCHEmissionCoverage','A transmitted or negative SR requires an actual owned binary procedure decision.');
    end
    if row.NativeWaveformExecuted
        assert(row.Transport=="PUCCH" && row.Disposition=="native_PUCCH_transmitted_modeled_control" && ...
            ~isempty(emissions) && nnz(string({emissions.SHA256})==row.EmissionSHA256)==1, ...
            'sixgr:abstraction:PUCCHEmissionCoverage','A claimed transmitter must have exactly one retained native emitter.');
        e=emissions(string({emissions.SHA256})==row.EmissionSHA256);
        assert(e.UEIndex==o.UEIndex && e.RNTI==o.RNTI && e.ServingCellID==o.CellID, ...
            'sixgr:abstraction:PUCCHEmissionCoverage','Emitter belongs to another UE/cell.');
        assert(string(e.ObligationID)==string(o.ResourceID) && ...
            string(e.ObligationSHA256)==localGrantDigest(o), ...
            'sixgr:abstraction:PUCCHEmissionCoverage', ...
            'A same-UE waveform cannot be reassigned to a different or changed UCI obligation.');
    elseif row.Transport=="PUCCH"
        assert(row.Disposition=="owned_negative_SR_no_transmission" && ...
            row.HARQBits+row.CSIPart1Bits+row.CSIPart2Bits==0 && row.SRBits>0 && ...
            row.SRPayloadKnown && row.PositiveSRCount==0 && row.EmissionSHA256=="", ...
            'sixgr:abstraction:PUCCHEmissionCoverage','No other missing producer may be relabeled silent SR.');
    else
        hashes=string(cellfun(@localGrantDigest,num2cell(state.GrantsUL),'UniformOutput',false));
        assert(row.Transport=="PUSCH" && row.Disposition=="validated_PUSCH_transport_no_PUCCH_emission" && ...
            row.ReplacementPUSCHGrantSHA256==o.PUSCHGrantSHA256 && ...
            nnz(hashes==o.PUSCHGrantSHA256)==1 && row.EmissionSHA256=="", ...
            'sixgr:abstraction:PUCCHEmissionCoverage','Replacement transport must be in the actual frozen UL population.');
    end
end
native=a.EmissionSHA256(a.NativeWaveformExecuted);
assert(numel(native)==numel(emissions) && numel(unique(native))==numel(native), ...
    'sixgr:abstraction:PUCCHEmissionCoverage','No duplicated or unowned PUCCH emissions.');
end
function h=localGrantDigest(g)
h=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(sixgr.util.jsonSafeValue(g)),'UTF-8'))));
end
