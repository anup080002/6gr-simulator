function validateGrantCalibrationPackage(data,matPath,policy)
%VALIDATEGRANTCALIBRATIONPACKAGE Do not trust serialized acceptance receipts.
assert(all(isfield(data,{'Schema','SourceClassification','Collections','Curves'})) && ...
    string(data.Schema)=="sixgr.grant_calibrated_sls_link/v1" && ...
    string(data.SourceClassification)=="executed_waveform_calibration" && ...
    isstruct(data.Collections) && isstruct(data.Curves) && ~isempty(data.Curves) && ...
    numel(data.Collections)==numel(data.Curves), ...
    'sixgr:abstraction:GrantCalibrationSpecification','Invalid grant-calibration package.');
root=string(fileparts(matPath)); if strlength(root)==0, root=string(pwd); end
owners=strings(1,numel(data.Curves)); ids=owners;
for k=1:numel(data.Curves)
    actual=sixgr.system.abstraction.reconstructGrantCalibrationCurve(data.Collections(k),policy,root);
    assert(isequaln(actual,data.Curves(k)), ...
        'sixgr:abstraction:GrantCalibrationReconstruction', ...
        'Serialized curve differs from the sealed waveform populations and independently rerun fitting.');
    owners(k)=string(jsonencode(actual.Key))+"|"+string(jsonencode(actual.RVSequence))+ ...
        "|"+string(jsonencode(actual.HARQSlotOffsets0));
    ids(k)=actual.CurveID;
end
assert(numel(unique(owners))==numel(owners) && numel(unique(ids))==numel(ids), ...
    'sixgr:abstraction:DuplicateCalibration','Duplicate runtime-key/RV/clock or curve-ID ownership.');
end
