function out = calibrateFTP3Loads(cases, policy, executeCase, outputFolder, options)
%CALIBRATEFTP3LOADS Measure baseline FTP3 load without qualifying an SLS study.
% Each callback must execute the frozen case through SystemLevelRunner and
% return its retained result. A converged load rate is not PHY/RF acceptance.
% Resume=true reuses only sealed, revalidated drops with identical source,
% software, policy, cases and seeds. Use a named file-backed callback; pass
% execution inputs through the case/request, not a captured workspace.
arguments
    cases table
    policy struct
    executeCase (1,1) function_handle
    outputFolder (1,1) string
    options.Resume (1,1) logical = false
end
localValidateInputs(cases,policy,outputFolder,options.Resume);
keys=localGroupKeys(cases,policy.measurement_direction);
groups=unique(keys,"stable");
for g=1:numel(groups)
    localValidateGroup(cases(keys==groups(g),:),policy);
end
sourceIdentity=localSourceIdentity(executeCase);
planPath=fullfile(outputFolder,"load_calibration_plan.mat");
if options.Resume
    assert(isfile(planPath),'sixgr:system:FTPLoadResumeIdentity', ...
        'Resume requires the retained load calibration plan.');
    saved=load(planPath);
    assert(all(isfield(saved,{'cases','policy','sourceIdentity'})) && ...
        isequaln(saved.cases,cases) && isequaln(saved.policy,policy) && ...
        isequaln(saved.sourceIdentity,sourceIdentity), ...
        'sixgr:system:FTPLoadResumeIdentity', ...
        'Resume cannot mix changed cases, seeds, policy, software or implementation.');
else
    mkdir(outputFolder);
    save(planPath,"cases","policy","sourceIdentity");
end
iterations=table(); rates=table();
for g=1:numel(groups)
    group=cases(keys==groups(g),:);
    target=double(group.TargetRUPercent(1));
    lowerRate=0; upperRate=NaN;
    rate=double(policy.initial_arrival_rate_per_cell_s);
    converged=false; measuredRU=NaN;
    for step=1:policy.maximum_iterations
        occupied=0; available=0;
        hashes=strings(height(group),1);
        for drop=1:height(group)
            folder=fullfile(outputFolder,groups(g), ...
                sprintf('iteration_%03d',step),sprintf('drop_%03d',drop));
            if ~isfolder(folder), mkdir(folder); end
            request=struct('Case',group(drop,:), ...
                'ArrivalRatePerCell_s',rate,'Iteration',step, ...
                'OutputFolder',string(folder), ...
                'FirstMeasurementTTI',policy.warmup_tti+1, ...
                'MeasurementDirection',string(policy.measurement_direction));
            requestPath=fullfile(folder,"request.mat");
            resultPath=fullfile(folder,"runtime_result.mat");
            checkpointPath=fullfile(folder,"validated_drop.mat");
            if isfile(requestPath)
                saved=load(requestPath,'request');
                assert(isequaln(saved.request,request), ...
                    'sixgr:system:FTPLoadResumeIdentity','Retained drop request differs.');
            else
                save(requestPath,"request");
            end
            try
                reused=isfile(checkpointPath);
                if reused
                    retained=load(checkpointPath,'checkpoint');
                    assert(isfile(resultPath) && ...
                        isequaln(retained.checkpoint.Request,request) && ...
                        retained.checkpoint.SourceIdentity==sourceIdentity && ...
                        strcmpi(retained.checkpoint.ResultSHA256, ...
                            sixgr.csi.studyFileSHA256(resultPath)), ...
                        'sixgr:system:FTPLoadResumeDigest', ...
                        'Retained load result changed or belongs to another execution.');
                    retained=load(resultPath,'result');
                    result=retained.result;
                else
                    assert(~isfile(resultPath), ...
                        'sixgr:system:FTPLoadUnsealedResult', ...
                        'An unsealed result is retained; do not overwrite or silently reuse it.');
                    result=executeCase(request);
                    save(resultPath,"result","-v7.3");
                end
                expected=struct('ArrivalRatePerCell_s',rate, ...
                    'SeedBundle',group.SeedBundle{drop}, ...
                    'PlannedExecutionArchitecture',string(group.PlannedExecutionArchitecture(drop)));
                identity=sixgr.system.validateS0LoadIteration(result,expected);
                if ~strcmpi(identity.BaseConfigSHA256,string(group.BaseConfigSHA256(drop))) || ...
                        ~strcmpi(identity.CalibrationSHA256,string(group.LinkCalibrationSHA256(drop)))
                    error('sixgr:system:FTPLoadIdentity', ...
                        'Executed base configuration or BLER package differs from the frozen case.');
                end
                measured=sixgr.system.measureResourceUtilization( ...
                    result.Details.SchedulerGrants, ...
                    result.Details.ResourceOpportunityTable, ...
                    string(policy.measurement_direction),policy.warmup_tti+1);
                if ~reused
                    checkpoint=struct('Request',request, ...
                        'SourceIdentity',sourceIdentity, ...
                        'ResultSHA256',sixgr.csi.studyFileSHA256(resultPath));
                    % A same-directory rename publishes a complete checkpoint.
                    % Unsealed results are preserved, never silently recomputed.
                    temporary=string(tempname(folder))+".mat";
                    save(temporary,"checkpoint");
                    [moved,message]=movefile(temporary,checkpointPath);
                    assert(moved,'sixgr:system:FTPLoadCheckpoint','%s',message);
                end
                writetable(measured.PerCellSlot,fullfile(folder,"resource_utilization.csv"));
            catch ME
                failure=struct('Identifier',string(ME.identifier), ...
                    'Message',string(ME.message),'CaseID',string(group.CaseID(drop)));
                save(fullfile(folder,"failure.mat"),"failure");
                rethrow(ME)
            end
            occupied=occupied+measured.OccupiedPRBSymbols;
            available=available+measured.AvailablePRBSymbols;
            evidence=struct('CaseID',string(group.CaseID(drop)), ...
                'DropID',string(group.IndependentDropID(drop)), ...
                'Rate',rate,'SeedBundle',result.Details.SeedBundle, ...
                'Backend',identity.PHYExecutionMode, ...
                'CalibrationSHA256',identity.CalibrationSHA256, ...
                'Grants',localHash(table2struct(result.Details.SchedulerGrants)), ...
                'Opportunities',localHash(table2struct(result.Details.ResourceOpportunityTable)), ...
                'Arrivals',localHash(table2struct(result.Details.TrafficArrivalEvents)));
            hashes(drop)=localHash(evidence);
        end
        measuredRU=100*occupied/available;
        row=table(groups(g),step,rate,target,measuredRU,occupied,available, ...
            height(group),localHash(hashes), ...
            string(group.BaseConfigSHA256(1)), ...
            string(group.LinkCalibrationSHA256(1)), ...
            string(group.PlannedExecutionArchitecture(1)), ...
            'VariableNames',{'CalibrationKey','Iteration','ArrivalRatePerCell_s', ...
            'TargetRUPercent','MeasuredRUPercent','OccupiedPRBSymbols', ...
            'AvailablePRBSymbols','IndependentDropCount','EvidenceSHA256', ...
            'BaseConfigSHA256','LinkCalibrationSHA256','ExecutionArchitecture'});
        iterations=[iterations;row]; %#ok<AGROW>
        writetable(iterations,fullfile(outputFolder,"load_calibration_iterations.csv"));
        if abs(measuredRU-target)<=policy.tolerance_percentage_points
            converged=true;
            row.MeasurementDirection=string(policy.measurement_direction);
            row.FirstMeasurementTTI=policy.warmup_tti+1;
            row.TolerancePercentagePoints=policy.tolerance_percentage_points;
            row.PolicySHA256=localHash(policy);
            row.Status="measured_baseline_load_converged_not_study_accepted";
            row.CalibrationSHA256=localHash(table2struct(row));
            rates=[rates;row]; %#ok<AGROW>
            writetable(rates,fullfile(outputFolder,"frozen_ftp3_rates.csv"));
            save(fullfile(outputFolder,"frozen_ftp3_rates.mat"),"rates","policy");
            break
        end
        if measuredRU<target, lowerRate=rate; else, upperRate=rate; end
        if isnan(upperRate)
            nextRate=min(rate*policy.bracket_expansion_factor, ...
                policy.maximum_arrival_rate_per_cell_s);
        else
            nextRate=(lowerRate+upperRate)/2;
        end
        if nextRate==rate, break; end
        rate=nextRate;
    end
    if ~converged
        error('sixgr:system:FTPLoadDidNotConverge', ...
            'Baseline load %s reached %.4f%% versus %.4f%%; measured iterations are retained.', ...
            groups(g),measuredRU,target);
    end
end
out=struct('Ok',true,'LoadConverged',true,'PrimaryStudyAccepted',false, ...
    'Rates',rates,'Iterations',iterations,'OutputFolder',outputFolder, ...
    'SourceSHA256',sourceIdentity);
end

function localValidateInputs(cases,p,folder,resume)
required=["CaseID","IndependentDropID","PopulationID","CalibrationRole", ...
    "TargetRUPercent","SeedBundle","BaseConfigSHA256", ...
    "PlannedExecutionArchitecture","LinkCalibrationSHA256"];
if isempty(cases) || ~all(ismember(required,string(cases.Properties.VariableNames))) || ...
        ~iscell(cases.SeedBundle) || strlength(folder)==0 || isfile(folder) || ...
        (~resume && isfolder(folder)) || (resume && ~isfolder(folder))
    error('sixgr:system:FTPLoadPlan', ...
        'A new output folder and complete baseline case/seed/config identities are required.');
end

numbers=["initial_arrival_rate_per_cell_s","maximum_arrival_rate_per_cell_s", ...
    "bracket_expansion_factor","maximum_iterations","tolerance_percentage_points", ...
    "minimum_independent_drops","warmup_tti"];
for field=numbers
    if ~isfield(p,field) || ~isnumeric(p.(field)) || ~isscalar(p.(field)) || ...
            ~isfinite(p.(field))
        error('sixgr:system:FTPLoadPolicy','Missing or invalid policy field %s.',field);
    end
end
if ~isfield(p,'measurement_direction') || ...
        ~isscalar(string(p.measurement_direction)) || ...
        ~ismember(string(p.measurement_direction),["DL","UL"]) || ...
        p.initial_arrival_rate_per_cell_s<=0 || ...
        p.maximum_arrival_rate_per_cell_s<p.initial_arrival_rate_per_cell_s || ...
        p.bracket_expansion_factor<=1 || p.maximum_iterations<1 || ...
        p.maximum_iterations~=fix(p.maximum_iterations) || ...
        p.tolerance_percentage_points<=0 || p.tolerance_percentage_points>=100 || ...
        p.minimum_independent_drops<1 || ...
        p.minimum_independent_drops~=fix(p.minimum_independent_drops) || ...
        p.warmup_tti<0 || p.warmup_tti~=fix(p.warmup_tti)
    error('sixgr:system:FTPLoadPolicy','Invalid load-calibration policy or measurement direction.');
end
if any(string(cases.CalibrationRole)~="baseline") || ...
        any(strlength(string(cases.CaseID))==0) || ...
        any(strlength(string(cases.IndependentDropID))==0) || ...
        any(strlength(string(cases.PopulationID))==0) || ...
        numel(unique(string(cases.CaseID)))~=height(cases) || ...
        any(~isfinite(double(cases.TargetRUPercent))) || ...
        any(double(cases.TargetRUPercent)<=0 | double(cases.TargetRUPercent)>=100) || ...
        any(~localIsSHA(cases.BaseConfigSHA256)) || ...
        any(~ismember(string(cases.PlannedExecutionArchitecture), ...
            ["waveform","calibrated_link_abstraction"])) || ...
        any(string(cases.PlannedExecutionArchitecture)=="waveform" & ...
            strlength(string(cases.LinkCalibrationSHA256))~=0) || ...
        any(string(cases.PlannedExecutionArchitecture)=="calibrated_link_abstraction" & ...
            ~localIsSHA(cases.LinkCalibrationSHA256))
    error('sixgr:system:FTPLoadPlan', ...
        'Cases require explicit baseline role, valid target, backend and matching calibration identity.');
end
end

function tf=localIsSHA(values)
tf=cellfun(@(v)~isempty(regexp(v,'^[0-9a-fA-F]{64}$','once')), ...
    cellstr(string(values)));
end

function keys=localGroupKeys(cases,direction)
keys=strings(height(cases),1);
for k=1:height(cases)
    identity=struct('PopulationID',string(cases.PopulationID(k)), ...
        'TargetRUPercent',double(cases.TargetRUPercent(k)), ...
        'Direction',string(direction), ...
        'BaseConfigSHA256',lower(string(cases.BaseConfigSHA256(k))), ...
        'ExecutionArchitecture',string(cases.PlannedExecutionArchitecture(k)), ...
        'LinkCalibrationSHA256',lower(string(cases.LinkCalibrationSHA256(k))));
    keys(k)=localHash(identity);
end
end

function localValidateGroup(group,p)
seeds=strings(height(group),1);
requiredSeeds=["GeometrySeed","ShadowSeed","TrafficSeed", ...
    "AntennaOrientationSeed","SchedulerSeed","PropagationSeed"];
for k=1:height(group)
    if ~isstruct(group.SeedBundle{k}) || ~isscalar(group.SeedBundle{k}) || ...
            ~all(isfield(group.SeedBundle{k},requiredSeeds))
        error('sixgr:system:FTPLoadSeeds', ...
            'Each drop requires the six explicit SystemLevelRunner component seeds.');
    end
    for name=requiredSeeds
        value=double(group.SeedBundle{k}.(name));
        if ~isscalar(value) || ~isfinite(value) || value<0 || ...
                value~=fix(value) || value>2^32-1
            error('sixgr:system:FTPLoadSeeds', ...
                'SeedBundle.%s must be an integer in [0, 2^32-1].',name);
        end
    end
    seeds(k)=localHash(group.SeedBundle{k});
end
if height(group)<p.minimum_independent_drops || ...
        numel(unique(string(group.IndependentDropID)))~=height(group) || ...
        numel(unique(seeds))~=height(group) || ...
        numel(unique(string(group.CaseID)))~=height(group)
    error('sixgr:system:FTPLoadDrops', ...
        'A baseline group requires the configured count of distinct drops, seeds and case IDs.');
end
end

function digest=localHash(value)
bytes=uint8(unicode2native(jsonencode(sixgr.util.jsonSafeValue(value)),"UTF-8"));
digest=string(sixgr.util.sha256Hex(bytes));
end

function identity=localSourceIdentity(executeCase)
% Hash dirty/untracked implementation content, not only the Git commit.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
files=dir(fullfile(root,'+sixgr','**','*.m'));
catalogs=[dir(fullfile(root,'simulator','configs','schema','*.yaml')); ...
    dir(fullfile(root,'simulator','configs','schema','*.json'))];
paths=sort([string(fullfile({files.folder},{files.name})).'; ...
    string(fullfile({catalogs.folder},{catalogs.name})).']);
callback=functions(executeCase);
assert(isfield(callback,'file') && isfile(callback.file) && ...
    any(string(callback.type)==["simple","scopedfunction"]), ...
    'sixgr:system:FTPLoadCallbackIdentity', ...
    'Use a named file-backed callback; captured anonymous/nested state is not resumable evidence.');
paths=unique([paths;string(callback.file)],'stable');
hashes=strings(numel(paths),1);
for k=1:numel(paths), hashes(k)=sixgr.csi.studyFileSHA256(paths(k)); end
identity=localHash(struct('Paths',paths,'SHA256',hashes, ...
    'Callback',string(callback.function),'MATLAB',version,'Toolboxes',ver));
end
