function [state,evidence]=resolveReceivedAccessULTiming(cfg,receipt)
% Connected timing from retained UE reception, not configured TA or SRS.
% Resolving this state does NOT mean that a connected UL waveform executed.
r=receipt.Result; sib=receipt.DecodedSIB1;
assert(isstruct(sib) && all(isfield(sib,{'MIBDecoded','BCHCrcPass','DCICrcPass', ...
    'DLSCHCrcPass','SIB1ASN1DecodeOk','SIB1SemanticValid','SIB1PayloadBits', ...
    'ReceivedDLTimingReference'})), ...
    'sixgr:system:MissingAccessDLClock','Retain decoded SIB1 and its actual received DL clock.');
for name=["MIBDecoded","BCHCrcPass","DCICrcPass","DLSCHCrcPass", ...
        "SIB1ASN1DecodeOk","SIB1SemanticValid"]
    assert(isequal(sib.(name),true),'sixgr:system:UnacceptedAccessSIB1', ...
        'Connected UL timing requires accepted received SIB1.');
end
% SIB1PayloadBytes is a byte COUNT in the receiver schema. Reparse the
% actual received bit vector; mutated cached tree fields are not authority.
[tree,meta]=sixgr.rrc.asn1.decodeSIB1UPER(sib.SIB1PayloadBits);
received=struct('SIB1RxTree',tree,'SIB1PayloadHashRx',meta.PayloadHash);
installed=sixgr.mac.ra.installDecodedSIB1RACHConfig(struct(),received);
common=installed.UECommonCellConfiguration;
reference=sib.ReceivedDLTimingReference;
assert(reference.Source=="received_SSB_timing_and_decoded_BCH" && ...
    reference.NCellID==r.CellId && reference.SSBIndex==sib.SSBIndex, ...
    'sixgr:system:AccessDLClockOwnerMismatch','Received clock belongs to a different cell or SSB.');
common.ReceivedDLTimingReference=reference;
range=sixgr.phy.frame.FrequencyRangeResolver.resolve( ...
    'CenterFrequencyHz',sixgr.util.structGet(cfg,'phy.fc_Hz',cfg.channel.fc_Hz));
common.ULTimingAdvanceOffset=sixgr.phy.frame.resolveULTimingAdvanceOffset(common,range.FrequencyRange);
required={'Msg2ScheduledSlot','Msg2DCICrcPass','Msg2PDSCHCrcPass','RAPIDMatches', ...
    'RARULGrantValid','RARWindowExpired','RARReceiverContext','DecodedRAR','RuntimeStageRows'};
assert(all(isfield(r,required)) && r.Msg2DCICrcPass && r.Msg2PDSCHCrcPass && ...
    r.RAPIDMatches && r.RARULGrantValid && ~r.RARWindowExpired, ...
    'sixgr:system:UnacceptedAccessRAR','Connected TAG needs an accepted, timely received RAR.');
rar=sixgr.mac.ra.decodeMACRAR(r.DecodedRAR.Bytes,r.RARReceiverContext);
assert(rar.RAPID==r.RARReceiverContext.PreambleIndex && ...
    r.RARReceiverContext.CarrierSCSkHz==common.InitialULBWP.SubcarrierSpacing_kHz, ...
    'sixgr:system:AccessRAROwnerMismatch','RAR must match this UE preamble and received UL numerology.');
rows=r.RuntimeStageRows;
row=rows(string(rows.StageName)=="Msg2" & rows.StageSlot==r.Msg2ScheduledSlot,:);
assert(height(row)==1 && row.ObservationSampleRateHz==reference.SampleRateHz && ...
    row.ObservationCompletionTime_s==row.ObservationEndSampleExclusive/row.ObservationSampleRateHz && ...
    reference.AvailableAtSample<=row.ObservationStartSample, ...
    'sixgr:system:AccessRARCompletionMismatch','Retain a unique actual RAR completion after broadcast availability.');
timing=sixgr.mac.ra.connectedTimingFromRAR(cfg,common,rar,r.Msg2ScheduledSlot, ...
    row.ObservationEndSampleExclusive,row.ObservationSampleRateHz);
state=struct('UEIndex',receipt.UEIndex,'ServingCellIndex',receipt.ServingCellIndex, ...
    'CommonCellConfiguration',common,'ConnectedULTiming',timing, ...
    'RARPayloadSHA256',string(sixgr.util.sha256Hex(uint8(rar.Bytes))), ...
    'Source',"received_SIB1_and_MAC_RAR_with_actual_receive_completion", ...
    'WaveformTimingApplied',false,'PhysicalSRSReceived',false);
if nargout>1
    evidence=table(receipt.UEIndex,receipt.ServingCellIndex,reference.NCellID, ...
        reference.SSBIndex,reference.DLPhaseOffsetSamples,reference.AvailableAtSample, ...
        r.Msg2ScheduledSlot,row.ObservationEndSampleExclusive,reference.SampleRateHz, ...
        timing.ReceivedRARTiming.Command,timing.ReceivedRARTiming.NTA_Tc, ...
        double(timing.Offset.NTAOffset_Tc),timing.TimingAdvanceEffectiveAtSample, ...
        timing.TimeAlignmentExpirySampleExclusive,false,false,state.Source,state.RARPayloadSHA256, ...
        'VariableNames',{'UEIndex','ServingCellIndex','NCellID','SSBIndex', ...
        'ReceivedDLPhaseOffset_samples','ReceivedDLClockAvailableAtSample', ...
        'RARSlot0Based','RARReceiveCompletionSample','SampleRate_Hz', ...
        'ReceivedTACommand','NTA_Tc','NTAOffset_Tc','TAEffectiveTransmitSample', ...
        'TimeAlignmentExpirySampleExclusive','WaveformTimingApplied','PhysicalSRSReceived', ...
        'Source','RARPayloadSHA256'});
end
end
