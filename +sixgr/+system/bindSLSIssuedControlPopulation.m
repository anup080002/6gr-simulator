function state=bindSLSIssuedControlPopulation(state,dl,dlCells,ul,ulCells)
% Keep issued DCI separate from the shared channels executing this slot.
% K0/K2 can move data to a later slot, but never move its control emission.
% These are authored scheduler inputs, NOT evidence of received control.
assert(isstruct(state) && isscalar(state) && all(isfield(state,{'TTI','AbsoluteSlot0'})), ...
    'sixgr:system:IssuedControlClock','Require the committed slot clock.');
validateattributes(state.TTI,{'numeric'},{'scalar','integer','positive','finite'});
assert(isnumeric(state.AbsoluteSlot0) && isreal(state.AbsoluteSlot0) && ...
    isscalar(state.AbsoluteSlot0) && isfinite(state.AbsoluteSlot0) && ...
    state.AbsoluteSlot0==state.TTI-1, ...
    'sixgr:system:IssuedControlClock','Issued control uses AbsoluteSlot0=TTI-1.');
populations={dl,ul}; owners={dlCells,ulCells}; directions=["DL","UL"];
for index=1:2
    grants=populations{index}; cells=owners{index}; direction=directions(index);
    assert(isstruct(grants) && isnumeric(cells) && numel(grants)==numel(cells) && ...
        all(isfinite(cells(:)) & cells(:)>0 & cells(:)==fix(cells(:))), ...
        'sixgr:system:IssuedControlPopulation','Every issued grant needs its serving-cell owner.');
    for k=1:numel(grants)
        g=grants(k);
        assert(all(isfield(g,{'Direction','ControlAbsoluteSlot','ScheduledAbsoluteSlot','RNTI'})), ...
            'sixgr:system:IssuedControlIdentity','Issued control requires explicit direction, control/data clocks and RNTI.');
        control=g.ControlAbsoluteSlot; data=g.ScheduledAbsoluteSlot;
        assert(isnumeric(control) && isreal(control) && isscalar(control) && ...
            isfinite(control) && control==state.AbsoluteSlot0 && ...
            isnumeric(data) && isreal(data) && isscalar(data) && isfinite(data) && ...
            data==fix(data) && data>=control, ...
            'sixgr:system:IssuedControlClock', ...
            'Retain DCI at its issued control slot, not its future/past shared-data execution slot.');
        assert(isscalar(string(g.Direction)) && string(g.Direction)==direction, ...
            'sixgr:system:IssuedControlIdentity','Grant direction disagrees with its issued population.');
        validateattributes(g.RNTI,{'numeric'},{'scalar','real','integer','positive','finite','<=',65535});
        if isfield(g,'SystemServingCellID')
            assert(isequal(double(g.SystemServingCellID),double(cells(k))), ...
                'sixgr:system:IssuedControlIdentity','Issued control cannot change the grant cell owner.');
        end
    end
    % Value snapshots preserve the complete authored DCI/PHY grant. Do not
    % rebuild bits from a data-slot grant or silently drop an empty slot.
    state.("IssuedGrants"+direction)=reshape(grants,[],1);
    state.("IssuedGrantCells"+direction)=reshape(cells,[],1);
end
state.IssuedControlPopulationSource="authored_scheduler_grants_not_received_control";
state.IssuedControlWaveformExecuted=false;
end
