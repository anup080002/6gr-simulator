function cfg = installRuntimeOperatingAuthority(cfg, sourceScenario)
%INSTALLRUNTIMEOPERATINGAUTHORITY Publish one immutable configured PHY authority.
%
% Legacy aliases remain available for compatibility, but this contract is
% the single configured operating point consumed by qualification and MIMO
% evidence. Contradictory source aliases are rejected before waveform
% execution instead of being resolved by first-path-wins behavior.

arguments
    cfg (1,1) struct
    sourceScenario (1,1) struct
end

localAssertSourceAliasesAgree(sourceScenario);

dl = localDirection(cfg, "DL");
ul = localDirection(cfg, "UL");
gnb = localAntenna(cfg, "gnb");
ue = localAntenna(cfg, "ue");
linkAdaptation = localLinkAdaptation(cfg);
mu = localMUScheduler(cfg);
features = localFeatureAuthority(cfg, sourceScenario);

authority = struct( ...
    "ContractVersion", "sixgr_runtime_operating_authority/v1", ...
    "SourceScenarioId", string(sixgr.util.structGet(sourceScenario, "meta.scenario_id", "")), ...
    "SourceConfigSHA256", string(sixgr.util.structGet(cfg, "meta.configHash", "")), ...
    "phy", struct("dl", dl, "ul", ul), ...
    "antenna", struct("gnb", gnb, "ue", ue), ...
    "link_adaptation", linkAdaptation, ...
    "scheduler", struct("mu_mimo", mu), ...
    "features", features);
authoritySHA256 = string(sixgr.mimo.hashMIMOConfig(authority));

cfg.runtime = authority;
cfg.runtime.OperatingAuthoritySHA256 = authoritySHA256;
cfg.runtime.ParameterProvenanceTable = localProvenanceTable(cfg, sourceScenario);
cfg = sixgr.util.structSet(cfg, "resolved_runtime_view.operating_authority", authority);
cfg = sixgr.util.structSet(cfg, "resolved_runtime_view.operating_authority_sha256", char(authoritySHA256));
end

function row = localDirection(cfg, direction)
direction = upper(string(direction));
if direction == "DL"
    root = "phy.pdsch";
    logicalPorts = localFirstFinite(cfg, [root + ".numPorts", root + ".nPorts", ...
        root + ".NumAntennaPorts", root + ".numAntennaPorts"], NaN);
else
    root = "phy.pusch";
    logicalPorts = localFirstFinite(cfg, [root + ".NumAntennaPorts", ...
        root + ".numAntennaPorts", root + ".numPorts"], NaN);
end
layers = localFirstFinite(cfg, [root + ".numLayers", root + ".nLayers", ...
    root + ".rank"], NaN);
if ~isfinite(logicalPorts)
    logicalPorts = layers;
end
row = struct( ...
    "Direction", direction, ...
    "NumLayers", double(layers), ...
    "NumLogicalPorts", double(logicalPorts), ...
    "Modulation", string(sixgr.util.structGet(cfg, root + ".modulation", "")), ...
    "MCSIndex", double(sixgr.util.structGet(cfg, root + ".mcsIndex", NaN)), ...
    "MCSTable", string(sixgr.util.structGet(cfg, root + ".mcsTable", "")), ...
    "TargetCodeRate", double(localFirstFinite(cfg, ...
        [root + ".codeRate", root + ".targetCodeRate"], NaN)), ...
    "PRBStart", double(localFirstFinite(cfg, [root + ".prbStart", root + ".PRBStart"], NaN)), ...
    "NumPRB", double(localFirstFinite(cfg, [root + ".numPRB", root + ".NumPRB"], NaN)), ...
    "SymbolAllocation", double(sixgr.util.structGet(cfg, root + ".symbolAllocation", [])), ...
    "ExecutionProfile", string(sixgr.util.structGet(cfg, root + ".executionProfile", "")), ...
    "RankSelectionPolicy", string(sixgr.util.structGet(cfg, ...
        "phy.linkAdaptation.rankPolicy", "")));
end

function row = localAntenna(cfg, role)
role = lower(string(role));
if role == "gnb"
    elementPaths = ["antenna.bs.numElements", "scenario.bs.nTxAnt", "phy.nTxAnt"];
    portPaths = ["antenna.bs.numPorts", "scenario.bs.numRFChains", ...
        "phy.pdsch.numPorts", "phy.pdsch.nPorts"];
    rfPaths = ["antenna.bs.numRFChains", "scenario.bs.numRFChains", ...
        "rf.bs.numRFChains"];
    txRFPaths = ["antenna.bs.numTxRFChains", "scenario.bs.numTxRFChains", ...
        "antenna_and_array.bs_num_txrus"];
    rxRFPaths = ["antenna.bs.numRxRFChains", "scenario.bs.numRxRFChains", ...
        "antenna_and_array.bs_num_rxrus"];
    geometryPaths = ["antenna.bs.geometry", "scenario.bs.arrayGeometry"];
else
    elementPaths = ["antenna.ue.numElements", "scenario.ue.nRxAnt", "phy.nRxAnt"];
    portPaths = ["antenna.ue.numPorts", "scenario.ue.numRFChains", ...
        "phy.pusch.NumAntennaPorts", "phy.pusch.numAntennaPorts"];
    rfPaths = ["antenna.ue.numRFChains", "scenario.ue.numRFChains", ...
        "rf.ue.numRFChains"];
    txRFPaths = ["antenna.ue.numTxRFChains", "scenario.ue.numTxRFChains", ...
        "antenna_and_array.ue_num_txrus"];
    rxRFPaths = ["antenna.ue.numRxRFChains", "scenario.ue.numRxRFChains", ...
        "antenna_and_array.ue_num_rxrus"];
    geometryPaths = ["antenna.ue.geometry", "scenario.ue.arrayGeometry"];
end
elements = localFirstFinite(cfg, elementPaths, NaN);
ports = localFirstFinite(cfg, portPaths, NaN);
rfChains = localFirstFinite(cfg, rfPaths, ports);
txRFChains = localFirstFinite(cfg, txRFPaths, rfChains);
rxRFChains = localFirstFinite(cfg, rxRFPaths, rfChains);
row = struct( ...
    "Role", role, ...
    "NumPhysicalElements", double(elements), ...
    "NumLogicalPorts", double(ports), ...
    "NumRFChains", double(rfChains), ...
    "NumTxRFChains", double(txRFChains), ...
    "NumRxRFChains", double(rxRFChains), ...
    "Geometry", localFirstText(cfg, geometryPaths, ""), ...
    "HybridBeamformingEnabled", logical(sixgr.util.structGet(cfg, ...
        "phy.beamManagement.hybridBeamformingEnabled", false)));
end

