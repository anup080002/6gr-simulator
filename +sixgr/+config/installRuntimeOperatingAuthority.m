function value = localFirstFinite(cfg, paths, defaultValue)
value = double(defaultValue);
for path = string(paths)
    candidate = sixgr.util.structGet(cfg, path, []);
    if (isnumeric(candidate) || islogical(candidate)) && isscalar(candidate) && isfinite(double(candidate))
        value = double(candidate);
        return;
    end
end
end

function value = localFirstText(cfg, paths, defaultValue)
value = string(defaultValue);
for path = string(paths)
    candidate = string(sixgr.util.structGet(cfg, path, ""));
    if isscalar(candidate) && strlength(strtrim(candidate)) > 0
        value = candidate;
        return;
    end
end
end

function text = localValueText(value)
if isempty(value)
    text = "";
elseif ischar(value) || isstring(value)
    text = strjoin(string(value(:).'), "|");
elseif isnumeric(value) || islogical(value)
    text = string(mat2str(value));
else
    text = string(jsonencode(value));
end
end
