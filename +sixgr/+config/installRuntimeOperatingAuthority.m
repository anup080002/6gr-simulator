function localAssertFeatureDependencies(s)
csiEnabled = localRequiredBoolean(s, "reference_signals.csi_reporting_enabled");
ptrsEnabled = localRequiredBoolean(s, "reference_signals.ptrs_enabled");
ptrsCorrectionEnabled = localRequiredBoolean(s, ...
    "reference_signals.ptrs_cpe_correction_enabled");
if ptrsCorrectionEnabled && ~ptrsEnabled
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "reference_signals.ptrs_cpe_correction_enabled=true requires ptrs_enabled=true.");
end
harqEnabled = localRequiredBoolean(s, "harq.enabled");
harqDiagnosticsEnabled = localRequiredBoolean(s, ...
    "simulation.harq_diagnostics_enabled");
if harqDiagnosticsEnabled && ~harqEnabled
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "simulation.harq_diagnostics_enabled=true requires harq.enabled=true.");
end
for path = ["reference_signals.cqi_reporting_enabled", ...
        "reference_signals.pmi_reporting_enabled", ...
        "reference_signals.ri_reporting_enabled", ...
        "reference_signals.cri_reporting_enabled"]
    if localRequiredBoolean(s, path) && ~csiEnabled
        error("sixgr:config:ContradictoryRuntimeAuthority", ...
            "%s=true requires reference_signals.csi_reporting_enabled=true.", ...
            char(path));
    end
end
ssbEnabled = localRequiredBoolean(s, "reference_signals.ssb_enabled");
pbchEnabled = localRequiredBoolean(s, "reference_signals.pbch_enabled");
pdcchEnabled = localRequiredBoolean(s, "control.pdcch_enabled");
pdcchBlindSearchEnabled = localRequiredBoolean(s, ...
    "control.blind_search_enabled");
pdcchDMRSEnabled = localRequiredBoolean(s, ...
    "reference_signals.pdcch_dmrs_enabled");
sib1Enabled = localRequiredBoolean(s, "initial_access.sib1.enabled");
beamSweepEnabled = localRequiredBoolean(s, "mimo.beam_sweep_enabled");
trackingEnabled = localRequiredBoolean(s, ...
    "reference_signals.tracking_rs_enabled");
trsEnabled = localRequiredBoolean(s, "reference_signals.trs_enabled");
if pbchEnabled && ~ssbEnabled
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "reference_signals.pbch_enabled=true requires ssb_enabled=true.");
end
if pdcchEnabled ~= pdcchDMRSEnabled
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "control.pdcch_enabled and reference_signals.pdcch_dmrs_enabled must agree.");
end
if pdcchBlindSearchEnabled && ~pdcchEnabled
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "control.blind_search_enabled=true requires control.pdcch_enabled=true.");
end
if sib1Enabled && ~(ssbEnabled && pbchEnabled && pdcchEnabled)
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "initial_access.sib1.enabled=true requires SSB, PBCH and PDCCH enabled.");
end
if sib1Enabled && ~pdcchBlindSearchEnabled
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "initial_access.sib1.enabled=true requires control.blind_search_enabled=true.");
end
if beamSweepEnabled && ~ssbEnabled
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "mimo.beam_sweep_enabled=true requires reference_signals.ssb_enabled=true.");
end
if trackingEnabled && ~trsEnabled
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "reference_signals.tracking_rs_enabled=true requires trs_enabled=true.");
end
end

function value = localRequiredBoolean(s, path)
raw = sixgr.util.structGet(s, path, []);
if ~localIsBooleanScalar(raw)
    error("sixgr:config:MissingYAMLFeatureAuthority", ...
        "Feature authority %s must be an explicit YAML boolean.", char(path));
end
value = logical(raw);
end

