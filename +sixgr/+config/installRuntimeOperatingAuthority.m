function feature = localDerivedFeature(cfg, s, sourcePath, runtimePath)
sourceValue = sixgr.util.structGet(s, sourcePath, []);
if isempty(sourceValue)
    error("sixgr:config:MissingYAMLFeatureAuthority", ...
        "Derived feature authority %s must be explicit in YAML.", ...
        char(sourcePath));
end
runtimeValue = sixgr.util.structGet(cfg, runtimePath, []);
if ~localIsBooleanScalar(runtimeValue)
    error("sixgr:config:MissingRuntimeFeatureConsumer", ...
        "YAML feature %s has no boolean runtime consumer at %s.", ...
        char(sourcePath), char(runtimePath));
end
feature = struct( ...
    "Enabled", logical(runtimeValue), ...
    "SourceYAMLPath", string(sourcePath), ...
    "SourceYAMLValue", localValueText(sourceValue), ...
    "RuntimeConsumerPaths", string(runtimePath), ...
    "Authority", "resolved_scenario_yaml", ...
    "Status", "yaml_target_case_derived_runtime_consumer_exact");
end

function feature = localFeature(cfg, s, sourcePath, runtimePaths)
sourceValue = sixgr.util.structGet(s, sourcePath, []);
if ~localIsBooleanScalar(sourceValue)
    error("sixgr:config:MissingYAMLFeatureAuthority", ...
        "Feature authority %s must be an explicit YAML boolean.", ...
        char(sourcePath));
end
enabled = logical(sourceValue);
for runtimePath = string(runtimePaths)
    runtimeValue = sixgr.util.structGet(cfg, runtimePath, []);
    if ~localIsBooleanScalar(runtimeValue)
        error("sixgr:config:MissingRuntimeFeatureConsumer", ...
            "YAML feature %s has no boolean runtime consumer at %s.", ...
            char(sourcePath), char(runtimePath));
    end
    if logical(runtimeValue) ~= enabled
        error("sixgr:config:YAMLFeatureAuthorityBypassed", ...
            "YAML feature %s=%d disagrees with runtime consumer %s=%d.", ...
            char(sourcePath), enabled, char(runtimePath), logical(runtimeValue));
    end
end
feature = struct( ...
    "Enabled", enabled, ...
    "SourceYAMLPath", string(sourcePath), ...
    "RuntimeConsumerPaths", string(runtimePaths(:).'), ...
    "Authority", "resolved_scenario_yaml", ...
    "Status", "configured_runtime_consumer_exact");
end

function localAssertBooleanAliases(s, concept, paths)
values = false(0, 1);
sources = strings(0, 1);
for path = string(paths)
    value = sixgr.util.structGet(s, path, []);
    if isempty(value)
        continue;
    end
    if ~localIsBooleanScalar(value)
        error("sixgr:config:InvalidRuntimeAuthorityAlias", ...
            "%s alias %s must be one boolean scalar.", concept, path);
    end
    values(end + 1, 1) = logical(value); %#ok<AGROW>
    sources(end + 1, 1) = path; %#ok<AGROW>
end
if numel(unique(values)) > 1
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "%s aliases disagree before execution: %s.", concept, ...
        char(strjoin(sources + "=" + string(double(values)), ", ")));
end
end

function tf = localIsBooleanScalar(value)
tf = (islogical(value) || isnumeric(value)) && isscalar(value) && ...
    isfinite(double(value)) && any(double(value) == [0 1]);
end

function localAssertNumericAliases(s, concept, paths)
values = zeros(0,1);
sources = strings(0,1);
for path = string(paths)
    value = sixgr.util.structGet(s, path, []);
    if isempty(value)
        continue;
    end
    if ~(isnumeric(value) || islogical(value)) || ~isscalar(value) || ~isfinite(double(value))
        error("sixgr:config:InvalidRuntimeAuthorityAlias", ...
            "%s alias %s must be one finite numeric scalar.", concept, path);
    end
    values(end+1,1) = double(value); %#ok<AGROW>
    sources(end+1,1) = path; %#ok<AGROW>
end
if numel(unique(values)) > 1
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "%s aliases disagree before execution: %s.", concept, ...
        char(strjoin(sources + "=" + string(values), ", ")));
end
end

function localAssertTextAliases(s, concept, paths, mcsIndex)
values = strings(0,1);
sources = strings(0,1);
for path = string(paths)
    value = string(sixgr.util.structGet(s, path, ""));
    if ~isscalar(value) || strlength(strtrim(value)) == 0
        continue;
    end
    values(end+1,1) = upper(strtrim(value)); %#ok<AGROW>
    sources(end+1,1) = path; %#ok<AGROW>
end
if numel(unique(values)) > 1
    error("sixgr:config:ContradictoryRuntimeAuthority", ...
        "%s aliases disagree before execution: %s.", concept, ...
        char(strjoin(sources + "=" + values, ", ")));
end
% MCS is recorded here only as provenance context; its modulation mapping
% is validated by resolveMCSProfile in buildInternalConfig.
if ~isscalar(mcsIndex) %#ok<ISCLSTR>
    error("sixgr:config:InvalidRuntimeAuthorityAlias", ...
        "%s MCS context must be scalar.", concept);
end
end

function T = localProvenanceTable(cfg, s)
