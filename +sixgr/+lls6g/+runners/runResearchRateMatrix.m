function out=runResearchRateMatrix(cfg,configPath,outputDir,runTag)
%RUNRESEARCHRATEMATRIX Compare observed goodput without changing link budget.
% Negative CRC/BLER results remain negative; completing a comparison does
% not mean all candidates passed or that the selected point is qualified.
assert(cfg.execution.max_parallel_jobs==1 && cfg.execution.repeat_count==1 && ...
    ~cfg.execution.stop_on_failure && cfg.execution.save_combined_summary, ...
    'sixgr:research:RateMatrixExecutionPolicy', ...
    'Rate comparison requires one worker, one repeat, all candidates and saved summaries.');
assert(isfield(cfg.execution,'maximum_observed_bler'), ...
    'sixgr:research:MissingBLERSelectionGate','Configure execution.maximum_observed_bler explicitly.');
paths=string(cfg.scenarios(:)); configs=cell(numel(paths),1);
for k=1:numel(paths)
    if ~isfile(paths(k)), paths(k)=fullfile(fileparts(configPath),paths(k)); end
    configs{k}=sixgr.lls6g.config.loadScenarioConfig(paths(k));
end
sixgr.phy.research.assertComparableRateConfigs(configs);
if strlength(string(runTag))==0, runTag=string(datetime('now','Format','yyyyMMdd_HHmmss_SSS')); end
assert(~isempty(regexp(char(runTag),'^[A-Za-z0-9_.-]+$','once')) && ...
    ~any(string(runTag)==[".",".."]),'sixgr:research:InvalidRunTag','Use a simple run tag.');
root=fullfile(outputDir,'lls',char(cfg.meta.matrix_id),char(runTag));
assert(~isfolder(root),'sixgr:research:RunAlreadyExists','Refusing to overwrite %s.',root);
mkdir(root); mkdir(fullfile(root,'meta'));
sixgr.util.jsonWrite(fullfile(root,'meta','matrix_config_resolved.json'),cfg);
sixgr.lls6g.config.writeYAML(fullfile(root,'meta','matrix_config_resolved.yaml'),cfg);
copyfile(configPath,fullfile(root,'meta','matrix_input.yaml'));
meta=struct('Status',"running",'ExecutionCompleted',false,'AllCandidatesPassed',false, ...
    'ResearchClass',"optional_research_experiment",'StandardNR',false, ...
    'SelectionMeaning',"best_observed_bidirectional_goodput_among_configured_candidates", ...
    'SelectionGate',"both_directions_observed_BLER_at_or_below_configured_limit", ...
    'MaximumObservedBLER',cfg.execution.maximum_observed_bler, ...
    'StatisticallyQualified',false,'GlobalOptimumClaimed',false);
manifest=fullfile(root,'meta','matrix_manifest.json'); sixgr.util.jsonWrite(manifest,meta);
rows=struct([]);
try
    for k=1:numel(paths)
        result=sixgr.lls6g.runners.runSingle(paths(k),fullfile(root,'runs'),"candidate_"+k);
        S=result.SummaryTable; T=result.TrialTable; s=result.Config.toStruct();
        dl=S(S.Direction=="DL",:); ul=S(S.Direction=="UL",:);
        assert(height(dl)==1 && height(ul)==1 && dl.HorizonSeconds==ul.HorizonSeconds);
        assert(sum(T.TBSBits(T.CRCPass & T.TBExact))==sum(S.DeliveredUniqueBits), ...
            'sixgr:research:GoodputAccountingMismatch','Candidate summary must reconcile with actual successful unique TBs.');
        eligible=dl.BLER<=cfg.execution.maximum_observed_bler && ul.BLER<=cfg.execution.maximum_observed_bler;
        row=struct('ScenarioID',result.Config.ScenarioID,'ConfigHash',result.Config.ConfigHash, ...
            'RunFolder',result.RunFolder,'DLTargetCodeRate',s.research_dl.target_code_rate, ...
            'ULTargetCodeRate',s.research_ul.target_code_rate,'ReferenceSNRdB',s.simulation.snr_db, ...
            'Layers',s.research_dl.num_layers,'HorizonSeconds',dl.HorizonSeconds, ...
            'DLTransportBlocks',dl.TransportBlocks,'ULTransportBlocks',ul.TransportBlocks, ...
            'DLBLER',dl.BLER,'ULBLER',ul.BLER,'DLGoodputBitsPerSecond',dl.GoodputBitsPerSecond, ...
            'ULGoodputBitsPerSecond',ul.GoodputBitsPerSecond, ...
            'CombinedGoodputBitsPerSecond',dl.GoodputBitsPerSecond+ul.GoodputBitsPerSecond, ...
            'AllTBsPassed',result.ResultOk,'EligibleForSelection',eligible, ...
            'Source',"actual_coded_research_waveform",'StandardNR',false);
        if isempty(rows), rows=row; else, rows(end+1)=row; end %#ok<AGROW>
        sixgr.util.csvWriteTable(fullfile(root,'reports','csv','rate_comparison.csv'),struct2table(rows));
        fprintf('RESEARCH_RATE_CANDIDATE rateDL=%g rateUL=%g DL=%g UL=%g BLER_DL=%g BLER_UL=%g eligible=%d\n', ...
            row.DLTargetCodeRate,row.ULTargetCodeRate,row.DLGoodputBitsPerSecond, ...
            row.ULGoodputBitsPerSecond,row.DLBLER,row.ULBLER,eligible);
    end
    comparisons=struct2table(rows);
    ranked=sortrows(comparisons(comparisons.EligibleForSelection,:), ...
        'CombinedGoodputBitsPerSecond','descend');
    best=ranked(1:min(1,height(ranked)),:); % Empty means no measured candidate met the gate.
    sixgr.util.csvWriteTable(fullfile(root,'reports','csv','eligible_ranked.csv'),ranked);
    sixgr.util.csvWriteTable(fullfile(root,'reports','csv','best_observed.csv'),best);
    imageDir=fullfile(root,'reports','image'); mkdir(imageDir);
    fig=figure('Visible','off'); closeFig=onCleanup(@()close(fig)); %#ok<NASGU>
    bar(categorical(comparisons.ScenarioID), ...
        [comparisons.DLGoodputBitsPerSecond comparisons.ULGoodputBitsPerSecond]/1e9,'stacked');
    ylabel('Delivered unique TB Gbit/s over full TDD horizon'); legend('DL','UL','Location','best');
    title('Observed configured candidates; not global optimum or statistical qualification');
    exportgraphics(fig,fullfile(imageDir,'rate_goodput.png'));
    meta.Status="completed"; meta.ExecutionCompleted=true;
    meta.AllCandidatesPassed=all(comparisons.AllTBsPassed); meta.SelectionAvailable=~isempty(best);
    if ~isempty(best), meta.SelectedScenarioID=best.ScenarioID; end
    sixgr.util.jsonWrite(manifest,meta);
    out=struct('Ok',meta.AllCandidatesPassed,'ExecutionCompleted',true, ...
        'RunFolder',string(root),'ComparisonTable',comparisons,'BestObservedTable',best);
catch ME
    meta.Status="failed"; meta.ErrorIdentifier=string(ME.identifier); meta.ErrorMessage=string(ME.message);
    sixgr.util.jsonWrite(manifest,meta); rethrow(ME);
end
end
