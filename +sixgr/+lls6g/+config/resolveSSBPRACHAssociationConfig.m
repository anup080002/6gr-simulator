function out=resolveSSBPRACHAssociationConfig(r)
% Exact TS 38.331 RACH-ConfigCommon choice/count domain; no schedule policy.
assert(isstruct(r)&&isscalar(r)&&all(isfield(r, ...
    {'ssb_per_rach_choice','cb_preambles_per_ssb','preamble_count'})), ...
    'sixgr:lls6g:config:MissingSSBPRACHAssociation','Declare SSB/RO choice, CB count and total preambles.');
c=r.ssb_per_rach_choice;
assert((isstring(c)&&isscalar(c)&&~ismissing(c))||(ischar(c)&&isrow(c)), ...
    'sixgr:lls6g:config:InvalidSSBPRACHAssociation','SSB/RO choice must be scalar text.');
c=string(c); tokens=["oneEighth","oneFourth","oneHalf","one","two","four","eight","sixteen"];
ratios=[1/8 1/4 1/2 1 2 4 8 16];
assert(any(c==tokens),'sixgr:lls6g:config:InvalidSSBPRACHAssociation','Invalid NR SSB/RO choice.');
n=ratios(c==tokens); count=r.cb_preambles_per_ssb; total=r.preamble_count;
for v={count,total}
    x=v{1}; assert(isnumeric(x)&&~islogical(x)&&isreal(x)&&isscalar(x)&&isfinite(x)&& ...
        x>=1&&x<=64&&x==fix(x),'sixgr:lls6g:config:InvalidSSBPRACHAssociation', ...
        'CB and total preamble counts must be original integers in 1..64.');
end
assert(count<=total && (n<1 || (mod(total,n)==0 && count<=total/n)) && ...
    ((n<=2 && mod(count,4)==0 && count<=64/max(1,n)) || ...
    (n>=4 && count<=64/n)), ...
    'sixgr:lls6g:config:InvalidSSBPRACHAssociation', ...
    'CB count must fit the ASN.1 choice and each total-preamble partition.');
wire=string(count); if n<=2, wire="n"+wire; end
out=struct('Choice',c,'SSBsPerRO',n,'CBPreamblesPerSSB',double(count), ...
    'TotalPreambles',double(total),'WireCBCount',wire);
end
