function coverage = registerWaveformLinkEvidence(registry, result, scfg, cfg, runtimeIdentity)
%REGISTERWAVEFORMLINKEVIDENCE Register fresh in-path link contract evidence.
%
% This adapter consumes only the in-memory result returned by the current
% waveform execution.  It never reads a prior CSV and never manufactures
% rows to satisfy a contract minimum.

arguments
    registry (1,1) sixgr.artifact.EvidenceRegistry
    result (1,1) struct
    scfg
    cfg (1,1) struct
    runtimeIdentity (1,1) struct = struct()
end

rows = repmat(struct("Domain","", "ArtifactType","", "FileName","", ...
    "Registered",false, "SourceRows",0, "Status","", "Reason",""), 0, 1);
raw = sixgr.util.structGet(result, "Link.RawTrials", struct());
dl = sixgr.util.structGet(raw, "DL", table());
if ~(istable(dl) && ~isempty(dl))
    rows(end+1,1) = localCoverage("pdsch", "CSV", ... %#ok<AGROW>
        "pdsch_bler_curve.csv", false, 0, "NOT_REGISTERED", ...
        "in_memory_dl_trials_missing");
else
    try
        curve = localBuildPDSCHBLERCurve(dl, scfg, cfg, runtimeIdentity);
        registry.registerTable("pdsch", "base", "pdsch_bler_curve.csv", ...
            curve, "sixgr.artifact.registerWaveformLinkEvidence.pdsch_bler_curve");
        rows(end+1,1) = localCoverage("pdsch", "CSV", ... %#ok<AGROW>
            "pdsch_bler_curve.csv", true, height(curve), "REGISTERED", "");
    catch cause
        rows(end+1,1) = localCoverage("pdsch", "CSV", ... %#ok<AGROW>
            "pdsch_bler_curve.csv", false, 0, "NOT_REGISTERED", ...
            string(cause.identifier) + " | " + string(cause.message));
    end
end

ul = sixgr.util.structGet(raw, "UL", table());
if ~(istable(ul) && ~isempty(ul))
    rows(end+1,1) = localCoverage("pusch", "CSV", ... %#ok<AGROW>
        "pusch_bler_curve.csv", false, 0, "NOT_REGISTERED", ...
        "in_memory_ul_trials_missing");
else
    try
        curve = localBuildPUSCHBLERCurve(ul, scfg, cfg, runtimeIdentity);
        registry.registerTable("pusch", "base", "pusch_bler_curve.csv", ...
            curve, "sixgr.artifact.registerWaveformLinkEvidence.pusch_bler_curve");
        rows(end+1,1) = localCoverage("pusch", "CSV", ... %#ok<AGROW>
            "pusch_bler_curve.csv", true, height(curve), "REGISTERED", "");
    catch cause
        rows(end+1,1) = localCoverage("pusch", "CSV", ... %#ok<AGROW>
            "pusch_bler_curve.csv", false, 0, "NOT_REGISTERED", ...
            string(cause.identifier) + " | " + string(cause.message));
    end
end

coverage = struct2table(rows, "AsArray", true);
end

function T = localBuildPUSCHBLERCurve(raw, scfg, cfg, runtimeIdentity)
required = ["ConfiguredSNR_dB","ChannelModelApplied","Rank", ...
    "MCSIndex","Modulation","CRCPass","ScenarioID","ConfigHash", ...
    "TransformPrecodingApplied","FrequencyHoppingApplied", ...
    "FrequencyHoppingMode"];
missing = setdiff(required, string(raw.Properties.VariableNames), "stable");
if ~isempty(missing)
    error("sixgr:artifact:PUSCHRawEvidenceMissingColumns", ...
        "In-memory UL trials lack required BLER fields: %s", ...
        strjoin(missing, ", "));
end

scenarioID = localScenarioID(scfg);
configHash = lower(localConfigHash(scfg));
localRequireIdentity(raw, "ScenarioID", scenarioID);
localRequireIdentity(raw, "ConfigHash", configHash);

eligible = true(height(raw), 1);
eligible = eligible & localLogicalColumn(raw, "FinalizedFlag", true);
eligible = eligible & localLogicalColumn(raw, "CRCApplicable", true);
eligible = eligible & localLogicalColumn(raw, "DecodeAttempted", true);
eligible = eligible & ~localLogicalColumn(raw, "FallbackFlag", false);
eligible = eligible & ~localLogicalColumn(raw, "PlaceholderFlag", false);
if ismember("TruthStatus", string(raw.Properties.VariableNames))
    eligible = eligible & lower(strtrim(string(raw.TruthStatus))) == ...
        "real_lls_evidence";
end
raw = raw(eligible, :);
if isempty(raw)
    error("sixgr:artifact:NoEligiblePUSCHTrials", ...
        "No finalized, decoded, non-fallback PUSCH trials are eligible.");
end

snr = double(raw.ConfiguredSNR_dB);
channel = strtrim(string(raw.ChannelModelApplied));
rankValue = double(raw.Rank);
mcs = double(raw.MCSIndex);
modulation = upper(strtrim(string(raw.Modulation)));
transform = localLogical(raw.TransformPrecodingApplied);
hoppingApplied = localLogical(raw.FrequencyHoppingApplied);
hopping = lower(strtrim(string(raw.FrequencyHoppingMode)));
validHopping = ismember(hopping, ["none","intra_slot","inter_slot"]);
if any(~isfinite(snr) | ~isfinite(rankValue) | ~isfinite(mcs) | ...
        strlength(channel) == 0 | strlength(modulation) == 0 | ...
        ~validHopping | (hoppingApplied ~= (hopping ~= "none")))
    error("sixgr:artifact:InvalidPUSCHOperatingPointIdentity", ...
        ["PUSCH BLER grouping fields must be finite/nonblank and the " ...
        "applied hopping flag must agree with the transmitter mode."]);
end
crcPass = localLogical(raw.CRCPass);

key = compose("snr=%.12g|channel=%s|rank=%d|mcs=%d|mod=%s|tp=%d|hop=%s", ...
    snr, channel, round(rankValue), round(mcs), modulation, transform, hopping);
[groups, keys] = findgroups(key);
design = localBLERDesign(cfg);
identity = localIdentity(scfg, cfg, runtimeIdentity);
out = repmat(localEmptyPUSCHBLERRow(), numel(keys), 1);
for index = 1:numel(keys)
    selected = groups == index;
    trials = nnz(selected);
    errors = nnz(~crcPass(selected));
    interval = sixgr.validation.BinomialIntervalEngine.exactTwoSided( ...
        errors, trials, design.ConfidenceLevel);
    first = find(selected, 1, "first");
    [stopReason, status, incomplete] = localQualificationStatus( ...
        trials, errors, interval.HalfWidth, design);
    operatingPointID = sixgr.util.sha256Hex(keys(index));
    out(index) = struct( ...
        "CampaignID", identity.RunID, ...
        "OperatingPointID", operatingPointID, ...
        "SNRdB", snr(first), ...
        "ChannelModel", channel(first), ...
        "Rank", rankValue(first), ...
        "MCSIndex", mcs(first), ...
        "Modulation", modulation(first), ...
        "TransformPrecoding", transform(first), ...
        "FrequencyHopping", hopping(first), ...
        "Trials", double(trials), ...
        "TBErrors", double(errors), ...
        "BLER", double(errors/trials), ...
        "ConfidenceLevel", design.ConfidenceLevel, ...
        "CILower", interval.Lower, ...
        "CIUpper", interval.Upper, ...
        "CIHalfWidth", interval.HalfWidth, ...
        "MinErrorsRequired", design.MinimumErrors, ...
        "QualificationProfile", design.Profile, ...
        "PublicationQualificationRequested", design.PublicationQualificationRequested, ...
        "PublicationEligible", status == "STATISTICALLY_QUALIFIED" && ~incomplete, ...
        "StopReason", stopReason, ...
        "Incomplete", incomplete, ...
        "Status", status, ...
        "ScenarioID", identity.ScenarioID, ...
        "ConfigHash", identity.ConfigHash, ...
        "EvidenceScope", "in_path", ...
        "RunID", identity.RunID, ...
        "ExecutionID", identity.ExecutionID, ...
        "CenterFrequencyHz", identity.CenterFrequencyHz, ...
        "BandwidthHz", identity.BandwidthHz, ...
        "SubcarrierSpacingHz", identity.SubcarrierSpacingHz, ...
        "IntervalMethod", interval.Method, ...
        "EvidenceUnit", "decoded_transport_block");
end
T = struct2table(out, "AsArray", true);
if strlength(identity.ExecutionID) == 0
    T.ExecutionID = [];
end
T = sortrows(T, ["SNRdB","ChannelModel","Rank","MCSIndex", ...
    "Modulation","TransformPrecoding","FrequencyHopping"]);
end

