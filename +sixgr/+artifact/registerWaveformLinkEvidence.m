function identity = localIdentity(scfg, cfg, runtimeIdentity)
identity = struct( ...
    "ScenarioID", localScenarioID(scfg), ...
    "ConfigHash", lower(localConfigHash(scfg)), ...
    "RunID", strtrim(string(sixgr.util.structGet(runtimeIdentity, ...
        "RunID", sixgr.util.structGet(cfg, "run.runTag", "")))), ...
    "ExecutionID", strtrim(string(sixgr.util.structGet(runtimeIdentity, ...
        "ExecutionID", sixgr.util.structGet(cfg, "run.executionID", "")))), ...
    "CenterFrequencyHz", localRequiredNumber(cfg, ...
        ["frequency.centerFrequencyHz","frequency.center_frequency_hz","channel.fc_Hz"]), ...
    "BandwidthHz", localRequiredNumber(cfg, ...
        ["frequency.bandwidthHz","frequency.bandwidth_hz","channel.bandwidth_Hz"]), ...
    "SubcarrierSpacingHz", 1e3 * localRequiredNumber(cfg, ...
        ["channel.subcarrierSpacing_kHz","frame.scs_khz","numerology.scs_khz"]));
if strlength(identity.RunID) == 0
    error("sixgr:artifact:RuntimeRunIDMissing", ...
        "In-path artifact registration requires the current logical RunID.");
end
end

function design = localBLERDesign(cfg)
base = sixgr.util.structGet(cfg, "validation.fixed_link_campaign", struct());
enabled = logical(sixgr.util.structGet(base, "enabled", false));
profile = lower(strtrim(string(sixgr.util.structGet(base, "profile", "diagnostic"))));
if ~isscalar(profile) || ~ismember(profile, ["full","diagnostic"])
    error("sixgr:artifact:InvalidBLERQualificationProfile", ...
        "validation.fixed_link_campaign.profile must be exactly 'full' " + ...
        "or 'diagnostic'; received '%s'.", strjoin(profile, ","));
end
design = struct( ...
    "Enabled", enabled, ...
    "Profile", profile, ...
    "PublicationQualificationRequested", enabled && profile == "full", ...
    "MinimumTrials", double(sixgr.util.structGet(base, ...
        "min_tb_per_point", NaN)), ...
    "MinimumErrors", double(sixgr.util.structGet(base, ...
        "min_errors_for_ci", NaN)), ...
    "MaximumCIHalfWidth", double(sixgr.util.structGet(base, ...
        "max_ci_half_width", NaN)), ...
    "ConfidenceLevel", double(sixgr.util.structGet(base, ...
        "confidence_level", 0.95)));
if ~(isscalar(design.ConfidenceLevel) && isfinite(design.ConfidenceLevel) && ...
        design.ConfidenceLevel > 0 && design.ConfidenceLevel < 1)
    error("sixgr:artifact:InvalidBLERConfidenceLevel", ...
        "PDSCH BLER evidence requires an explicit valid confidence level.");
end
end

function [reason, status, incomplete] = localQualificationStatus(trials, errors, halfWidth, design)
if ~design.Enabled
    reason = "fixed_sample_runtime_observation_not_qualification_campaign";
    status = "MEASURED";
    incomplete = false;
    return;
end
if ~(isfinite(design.MinimumTrials) && isfinite(design.MinimumErrors) && ...
        isfinite(design.MaximumCIHalfWidth))
    reason = "configured_statistical_design_incomplete";
    status = "NOT_EVALUATED";
    incomplete = true;
elseif design.Profile == "full" && design.MinimumErrors < 1
    reason = "full_profile_requires_positive_minimum_error_count";
    status = "NOT_EVALUATED";
    incomplete = true;
elseif trials < design.MinimumTrials
    reason = "minimum_trial_count_not_reached";
    status = "NOT_EVALUATED";
    incomplete = true;
elseif errors < design.MinimumErrors
    reason = "minimum_error_count_not_reached";
    status = "NOT_EVALUATED";
    incomplete = true;
elseif halfWidth > design.MaximumCIHalfWidth
    reason = "confidence_interval_half_width_not_reached";
    status = "NOT_EVALUATED";
    incomplete = true;
elseif design.Profile == "diagnostic"
    reason = "diagnostic_profile_design_criteria_reached";
    status = "MEASURED";
    incomplete = false;
else
    reason = "configured_trial_error_and_confidence_requirements_reached";
    status = "STATISTICALLY_QUALIFIED";
    incomplete = false;
end
end

function localRequireIdentity(T, column, expected)
observed = strtrim(string(T.(char(column))));
if any(ismissing(observed) | strlength(observed) == 0) || ...
        any(lower(observed) ~= lower(expected))
    error("sixgr:artifact:RawTrialIdentityMismatch", ...
        "In-memory raw trial %s does not match expected '%s'.", ...
        column, expected);
end
end

function value = localScenarioID(scfg)
if isobject(scfg) && isprop(scfg, "ScenarioID")
    value = strtrim(string(scfg.ScenarioID));
elseif isstruct(scfg)
    value = strtrim(string(sixgr.util.structGet(scfg, "scenario_id", ...
        sixgr.util.structGet(scfg, "meta.scenario_id", ""))));
else
    value = "";
end
if strlength(value) == 0
    error("sixgr:artifact:ScenarioIDMissing", ...
        "Runtime artifact registration requires ScenarioID.");
end
end

function value = localConfigHash(scfg)
if isobject(scfg) && isprop(scfg, "ConfigHash")
    value = strtrim(string(scfg.ConfigHash));
elseif isstruct(scfg)
    value = strtrim(string(sixgr.util.structGet(scfg, "ConfigHash", ...
        sixgr.util.structGet(scfg, "meta.configHash", ""))));
else
    value = "";
end
if strlength(value) ~= 64 || isempty(regexp(char(value), "^[0-9a-fA-F]{64}$", "once"))
    error("sixgr:artifact:ConfigHashMissing", ...
        "Runtime artifact registration requires a 64-character ConfigHash.");
end
end

function value = localRequiredNumber(cfg, paths)
value = NaN;
for path = string(paths(:)).'
    candidate = sixgr.util.structGet(cfg, path, []);
    if ~isempty(candidate)
        candidate = double(candidate(1));
        if isfinite(candidate)
            value = candidate;
            break;
        end
    end
end
if ~isfinite(value)
    error("sixgr:artifact:RadioIdentityMissing", ...
        "Runtime artifact registration lacks radio identity for %s.", ...
        strjoin(string(paths), "|"));
end
end

function value = localLogicalColumn(T, name, defaultValue)
if ismember(name, string(T.Properties.VariableNames))
    value = localLogical(T.(char(name)));
else
    value = repmat(logical(defaultValue), height(T), 1);
end
end

function value = localLogical(raw)
if islogical(raw)
    value = raw(:);
elseif isnumeric(raw)
    value = isfinite(double(raw(:))) & double(raw(:)) ~= 0;
else
    value = ismember(lower(strtrim(string(raw(:)))), ...
        ["true","1","yes","pass","ok"]);
end
end

