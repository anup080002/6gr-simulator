function out = sealBrowserArtifactClosure(runFolder, options)
%SEALBROWSERARTIFACTCLOSURE Materialize and audit exact terminal bytes.

arguments
    runFolder (1,1) string
    options.RunID (1,1) string = ""
    options.GeneratedAtUTC (1,1) string = ""
    options.MaxPasses (1,1) double {mustBeInteger,mustBePositive} = 3
    options.Required (1,1) logical = true
    options.ReplaceExistingRastersFromCSV (1,1) logical = true
end

passes = repmat(struct( ...
    "Pass", 0, "Materialization", struct(), "Receipt", struct(), ...
    "VisualAudit", struct(), "LineageClosure", struct()), 0, 1);
ok = false;
for passIndex = 1:options.MaxPasses
    % Geometry plots are producer-owned measured views. Bind their exact
    % current CSV and PNG bytes before the recursive visual audit.
    sixgr.visual.writeGeometryPlotLineage(runFolder);
    % Pass one may reuse a browser contract only when the Python publisher's
    % exact source-inventory and per-contract-file SHA-256 cache validates.
    % A later repair pass is forced after an audit failure.  This avoids
    % repeatedly rasterizing hundreds of unchanged plots without accepting
    % a version-only or timestamp-only cache as scientific evidence.
    forceMaterialization = passIndex > 1;
    materialization = sixgr.artifact.materializeBrowserContractArtifacts( ...
        runFolder, "Force", forceMaterialization, ...
        "ReplaceExistingRastersFromCSV", options.ReplaceExistingRastersFromCSV);
    materialization.RunID = options.RunID;
    generatedAt = options.GeneratedAtUTC;
    if strlength(strtrim(generatedAt)) == 0
        generatedAt = string(sixgr.util.utcNowISO8601());
    end
    materialization.GeneratedAtUTC = generatedAt;
    receipt = sixgr.artifact.writeBrowserPublicationReceipt( ...
        runFolder, materialization);
    sixgr.visual.writeGeometryPlotLineage(runFolder);
    visualAudit = sixgr.visual.finalizeRunVisualAudit(runFolder);
    lineageClosure = sixgr.artifact.verifyContractPlotLineageSources( ...
        runFolder);
    passes(end+1, 1) = struct( ...
        "Pass", double(passIndex), ...
        "Materialization", materialization, ...
        "Receipt", receipt, ...
        "VisualAudit", visualAudit, ...
        "LineageClosure", lineageClosure); %#ok<AGROW>
    ok = logical(sixgr.util.structGet(materialization, "Ok", false)) && ...
        logical(sixgr.util.structGet(visualAudit, "Ok", false)) && ...
        logical(sixgr.util.structGet(lineageClosure, "Ok", false));
    if ok
        break;
    end
end

out = struct( ...
    "Ok", logical(ok), ...
    "PassCount", double(numel(passes)), ...
    "Passes", passes, ...
    "Materialization", passes(end).Materialization, ...
    "Receipt", passes(end).Receipt, ...
    "VisualAudit", passes(end).VisualAudit, ...
    "LineageClosure", passes(end).LineageClosure);
if ~ok && options.Required
    message = sprintf(char( ...
        "Terminal browser closure failed after %d pass(es): " + ...
        "materialization=%d visual=%d lineage=%d."), ...
        numel(passes), ...
        logical(sixgr.util.structGet(passes(end).Materialization, "Ok", false)), ...
        logical(sixgr.util.structGet(passes(end).VisualAudit, "Ok", false)), ...
        logical(sixgr.util.structGet(passes(end).LineageClosure, "Ok", false)));
    error("sixgr:artifact:TerminalBrowserClosureFailed", "%s", message);
end
end
