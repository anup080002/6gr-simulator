classdef CheckpointExecutionHorizon
    % Explicit bounded continuation; never rewrite the saved scenario/hash.
    % Only derived execution clocks change. Channel, traffic, feedback,
    % grants, random streams, physical state and publication policy do not.
    methods (Static)
        function h=fromRequest(scenario,metadata,lastSlot,requestPath,requestHash)
            validateattributes(lastSlot,{'numeric'},{'real','scalar','finite','integer','positive'});
            original=double(sixgr.util.structGet(scenario,'run_control.total_slots',NaN));
            completed=double(metadata.CompletedSlot);
            assert(isfinite(original)&&original==fix(original)&&lastSlot>completed&&lastSlot<=original, ...
                'sixgr:checkpoint:InvalidExecutionHorizon', ...
                'finish_after_slot must exceed completed slot %g and not exceed original horizon %g.',completed,original);
            points=sixgr.util.structGet(scenario,'sweeps_and_matrix.snr_sweep.values_db',[]);
            enabled=logical(sixgr.util.structGet(scenario,'sweeps_and_matrix.snr_sweep.enabled',false));
            assert(string(sixgr.util.structGet(scenario,'scenario.runner_profile',''))=="waveform_bundle" && ...
                string(sixgr.util.structGet(scenario,'users.execution_model',''))=="slot_coupled_truth" && ...
                (~enabled || numel(points)==1) && ...
                double(sixgr.util.structGet(scenario,'simulation.monte_carlo_iterations',1))==1, ...
                'sixgr:checkpoint:UnsupportedBoundedHorizon', ...
                'An explicit continuation limit currently supports one coupled waveform operating point/realization only.');
            h=struct('Contract',"sixgr_checkpoint_execution_horizon/v1", ...
                'OriginalConfiguredSlots',original,'FinishAfterSlot',double(lastSlot), ...
                'ResumedAfterSlot',completed,'OriginalConfigHash',string(metadata.ConfigHash), ...
                'CheckpointStateSHA256',string(metadata.StateSHA256), ...
                'RequestPath',string(requestPath),'RequestSHA256',string(requestHash), ...
                'SlotNumbering',"1_based_inclusive",'PublicationMode',"full", ...
                'EvidenceScope',"bounded_checkpoint_repair_validation", ...
                'OriginalStudyHorizonCompleted',false,'PrimaryStudyEligible',false);
        end

        function cfg=apply(cfg,h)
            if isempty(fieldnames(h)), return; end
            assert(string(h.Contract)=="sixgr_checkpoint_execution_horizon/v1" && ...
                string(cfg.meta.configHash)==string(h.OriginalConfigHash) && ...
                double(cfg.run.totalSlots)==double(h.OriginalConfiguredSlots), ...
                'sixgr:checkpoint:HorizonIdentityMismatch', ...
                'The bounded execution clock must bind the original configuration, never a rewritten scenario.');
            limit=double(h.FinishAfterSlot);
            validateattributes(limit,{'double'},{'scalar','finite','integer','positive'});
            assert(limit>double(h.ResumedAfterSlot)&&limit<=double(h.OriginalConfiguredSlots), ...
                'sixgr:checkpoint:InvalidExecutionHorizon','Invalid bounded continuation interval.');
            slotMS=double(cfg.run.totalTime_ms)/double(cfg.run.totalSlots);
            validateattributes(slotMS,{'double'},{'scalar','finite','positive'});
            cfg.run.executionHorizon=h;
            cfg.run.totalSlots=limit;
            cfg.run.numTTI=limit;
            cfg.run.numFrames=ceil(limit*slotMS/10);
            cfg.run.totalTime_ms=limit*slotMS;
            % Preserve the original warmup and shorten only its intersection
            % with the actually executed prefix; do not rescale measurements.
            cfg.run.warmupSlots=min(double(cfg.run.warmupSlots),limit);
            cfg.run.measurementSlots=min(double(cfg.run.measurementSlots), ...
                max(0,limit-cfg.run.warmupSlots));
            cfg.run.warmupTime_ms=cfg.run.warmupSlots*slotMS;
            cfg.run.measurementTime_ms=cfg.run.measurementSlots*slotMS;
            cfg.system.simDuration_s=cfg.run.totalTime_ms/1000;
            cfg.system.warmupTime_s=cfg.run.warmupTime_ms/1000;
            cfg.system.measurementTime_s=cfg.run.measurementTime_ms/1000;
        end

        function assertResume(restored,cfg,slots,snrGrid)
            h=sixgr.util.structGet(cfg,'run.executionHorizon',struct());
            if isempty(fieldnames(h))
                assert(isequal(restored.SNRGrid,snrGrid)&&restored.FramesPerPoint==slots, ...
                    'sixgr:checkpoint:HorizonMismatch','The saved sweep and scheduling horizon must match.');
                return;
            end
            previous=sixgr.util.structGet(restored,'ExecutionHorizon',struct());
            savedHorizon=double(h.OriginalConfiguredSlots);
            if ~isempty(fieldnames(previous))
                assert(string(previous.OriginalConfigHash)==string(h.OriginalConfigHash)&& ...
                    previous.OriginalConfiguredSlots==h.OriginalConfiguredSlots, ...
                    'sixgr:checkpoint:HorizonIdentityMismatch','Saved bounded horizon has a different original identity.');
                savedHorizon=double(previous.FinishAfterSlot);
                assert(slots<=savedHorizon,'sixgr:checkpoint:HorizonExtension', ...
                    'Do not extend a bounded continuation after it may have censored future events.');
            end
            assert(numel(snrGrid)==1&&isequal(restored.SNRGrid,snrGrid)&& ...
                restored.FramesPerPoint==savedHorizon && slots==h.FinishAfterSlot && ...
                restored.CompletedSlot==h.ResumedAfterSlot && restored.CompletedSlot<slots && ...
                restored.FrameLocal==restored.CompletedSlot && restored.SweepIndex==1, ...
                'sixgr:checkpoint:HorizonMismatch', ...
                'Saved clock/sweep differs from the explicit bounded continuation.');
            queued=sixgr.util.structGet(restored,'PendingULGrants',struct([]));
            if ~isempty(queued)
                due=arrayfun(@sixgr.truth.runtimeULGrantSlot,queued);
                assert(all(due<=slots),'sixgr:checkpoint:HorizonCutsFrozenGrant', ...
                    'The requested endpoint would omit an already queued UL grant. Use an earlier checkpoint or a later endpoint.');
            end
        end

        function cfg=restorePublished(cfg,root)
            % Report recovery must not revert its denominator to the original
            % planned 100 slots after a declared 60-slot bounded execution.
            % Both independent persisted records must agree; no inference
            % from maximum trial slot, run name or a mutable launch YAML.
            limit=sixgr.runtime.CheckpointExecutionHorizon.readPublished(root);
            if isempty(fieldnames(limit)), return; end
            cfg=sixgr.runtime.CheckpointExecutionHorizon.apply(cfg,limit);
        end

        function limit=readPublished(root)
            limit=struct();
            limitPath=fullfile(root,'meta','continuation_execution_horizon.json');
            lineagePath=fullfile(root,'meta','checkpoint_resume.json');
            lineage=struct();
            if isfile(lineagePath), lineage=sixgr.util.jsonRead(lineagePath); end
            declared=sixgr.util.structGet(lineage,'ExecutionHorizon',struct());
            if isempty(fieldnames(declared)) && ~isfile(limitPath), return; end
            assert(~isempty(fieldnames(declared))&&isfile(limitPath), ...
                'sixgr:checkpoint:HorizonPublicationIdentity','Bounded publication needs its saved limit and checkpoint lineage.');
            limit=sixgr.util.jsonRead(limitPath);
            assert(isequaln(jsondecode(jsonencode(declared)),jsondecode(jsonencode(limit))) && ...
                string(sixgr.util.structGet(lineage,'CanonicalConfigHash',''))==string(limit.OriginalConfigHash) && ...
                string(sixgr.util.structGet(lineage,'ContinuationRequestSHA256',''))==string(limit.RequestSHA256) && ...
                string(sixgr.util.structGet(lineage,'StateSHA256',''))==string(limit.CheckpointStateSHA256), ...
                'sixgr:checkpoint:HorizonPublicationIdentity','Bounded publication identities disagree.');
            assert(string(limit.Contract)=="sixgr_checkpoint_execution_horizon/v1" && ...
                isnumeric(limit.FinishAfterSlot)&&isscalar(limit.FinishAfterSlot)&& ...
                isfinite(limit.FinishAfterSlot)&&fix(limit.FinishAfterSlot)==limit.FinishAfterSlot && ...
                limit.FinishAfterSlot>limit.ResumedAfterSlot && ...
                limit.FinishAfterSlot<=limit.OriginalConfiguredSlots, ...
                'sixgr:checkpoint:HorizonPublicationIdentity','Invalid persisted bounded horizon.');
        end
    end
end
