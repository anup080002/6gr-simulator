function [native,row,selection]=receivedPRACHAttemptSelection(cfg,runtimeSlot)
% Validate the frozen production admission; no host-authored RO replacement.
r=cfg.SharedReceivedPRACHSelection;
assert(isstruct(r) && isscalar(r) && all(isfield(r,{'ContractVersion','SHA256', ...
    'UEIndex','ServingCell','AcquisitionGenerationID','SelectedSSBTimingBindingSHA256', ...
    'SIB1TreeSHA256','PreparationSlot','NativeResolution','Validity','Selection'})), ...
    'sixgr:mac:ra:InvalidReceivedPRACHAttempt','Missing original received association receipt.');
payload=rmfield(r,'SHA256');
hash=sixgr.rrc.asn1.asn1SHA256Hex(uint8(unicode2native(jsonencode(payload),'UTF-8')));
assert(r.ContractVersion=="received_prach_attempt/v1" && string(r.SHA256)==string(hash) && ...
    isnumeric(runtimeSlot) && isscalar(runtimeSlot) && isfinite(runtimeSlot) && ...
    runtimeSlot==r.PreparationSlot && isfield(cfg,'SharedRATimingBinding'), ...
    'sixgr:mac:ra:InvalidReceivedPRACHAttempt','Do not alter or replay a received association at another preparation boundary.');
t=cfg.SharedRATimingBinding; selection=r.Selection; native=r.NativeResolution;
assert(t.BindingSHA256==r.SelectedSSBTimingBindingSHA256 && ...
    t.AcquisitionGenerationID==r.AcquisitionGenerationID && ...
    t.OriginalBCHBinding.ServingCell==r.ServingCell && ...
    t.OriginalBCHBinding.UEIndex==r.UEIndex && ...
    selection.Available && selection.SelectedSSBIndex0==t.SSBIndex && ...
    cfg.random_access.associated_ssb_index==t.SSBIndex && ...
    selection.SelectedSSBReferenceSHA256==t.BindingSHA256 && ...
    selection.SIB1TreeSHA256==r.SIB1TreeSHA256 && ...
    isequaln(native,cfg.phy.prach.timing), ...
    'sixgr:mac:ra:InvalidReceivedPRACHAttempt','Frozen received beam/cell/native calendar identity mismatch.');
if isfield(cfg,'UECommonCellConfiguration')
    assert(string(cfg.UECommonCellConfiguration.TreeHash)==r.SIB1TreeSHA256, ...
        'sixgr:mac:ra:InvalidReceivedPRACHAttempt','Installed received SI differs from the admitted association.');
end
row=selection.SelectedNativeOccasion;
if isfield(r,'CBPreambleChoice')
    % Older retained receipts remain readable. New production receipts seal
    % the actual policy decision, not a later mutable YAML interpretation.
    p=r.CBPreambleChoice;
    original=struct('cb_preamble_selection_policy',p.Policy, ...
        'cb_preamble_offset',p.ConfiguredOffset0);
    checked=sixgr.mac.ra.resolveCBPreambleOffset(original,r.UEIndex, ...
        selection.SelectedAssociationRow.CBPreambleCount);
    assert(p.UEIndex==r.UEIndex && p.Offset0==checked.Offset0 && ...
        p.ReceivedCBPreambleCount==checked.ReceivedCBPreambleCount && ...
        p.Classification==checked.Classification && ...
        isequal(p.NormativeUniformRandomSelection,false) && ...
        selection.PreambleIndex0==selection.SelectedAssociationRow.CBPreambleStart0+p.Offset0, ...
        'sixgr:mac:ra:InvalidReceivedPRACHAttempt', ...
        'Frozen CB policy and transmitted preamble must stay within the original received partition.');
end
assert(istable(row) && height(row)==1 && ...
    isequaln(row,native.Occasions(selection.SelectedAssociationRow.SourceOccasionRow,:)), ...
    'sixgr:mac:ra:InvalidReceivedPRACHAttempt','Retain the original selected native row.');
v=r.Validity;
% These INNER identities belong to the original validity/selection
% producers, whose canonical representation converts tables recursively.
% The outer attempt receipt above has its own unchanged JSON contract.
vhash=sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(v)));
nhash=sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(native)));
assert(string(vhash)==selection.ValiditySHA256 && string(nhash)==selection.NativeResolutionSHA256 && ...
    v.SIB1TreeSHA256==r.SIB1TreeSHA256 && v.NativeResolutionSHA256==string(nhash) && ...
    v.MIBContextSHA256==selection.MIBContextSHA256 && ...
    islogical(v.RepeatedValidity) && size(v.RepeatedValidity,1)==height(native.Occasions) && ...
    all(v.RepeatedValidity==v.RepeatedValidity(:,1),'all') && ...
    all(v.RepeatedValidity(selection.SelectedAssociationRow.SourceOccasionRow,:)), ...
    'sixgr:mac:ra:InvalidReceivedPRACHAttempt','Selected RO must retain its original decoded-input validity evaluation.');
end
