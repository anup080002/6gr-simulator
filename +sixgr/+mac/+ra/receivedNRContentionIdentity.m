function identity=receivedNRContentionIdentity(message,rarOwner,contentionOwner)
% TS38.321 V18.8.0 5.1.5: adopt received temporary C-RNTI after CCCH match.
% No final C-RNTI is encoded in the contention CE or RRCSetup.
id='sixgr:mac:ra:NRContentionIdentityAuthority';
assert(isa(rarOwner,'sixgr.phy.ra.RARReceiveWindow')&&rarOwner.Status=="matched"&& ...
    isa(contentionOwner,'sixgr.phy.ra.Msg4ReceiveWindow')&&contentionOwner.MAC.Status=="succeeded", ...
    id,'Use original accepted UE RAR and contention receiver owners.');
a=rarOwner.AcceptedResponse;b=contentionOwner.LastOutcome;
assert(a.Accepted && b.PDCCH.CausalGrantDecodeOk && b.PDSCH.Ok && ...
    b.Observation.IdentityMatches && isequaln(message,b.Message) && ...
    message.EncodingProfile=="nr_rrc_access_base_srb1_uper_v1" && isnan(message.FinalCRNTI), ...
    id,'Identity follows the original complete NR MAC decode, not an intended transmitter identity.');
for name=["RunId","UEId","AttemptId","CellId","ServingCell"]
    assert(isequal(rarOwner.RAConfig.(name),contentionOwner.RAConfig.(name)),id, ...
        'Received stages belong to different original attempts.');
end
assert(a.Observation.SampleRateHz==b.Observation.SampleRateHz && ...
    a.Observation.ObservationEndSampleExclusive<=b.Observation.ObservationStartSample && ...
    message.ContentionIdentity==contentionOwner.MAC.ExpectedIdentity && ...
    a.RAR.TemporaryCRNTI==contentionOwner.MAC.TemporaryCRNTI,id, ...
    'Use the original received temporary identity and causally later contention match.');
rnti=double(a.RAR.TemporaryCRNTI);
validateattributes(rnti,{'numeric'},{'scalar','real','finite','integer','>=',1,'<=',65522});
identity=struct('RNTI',rnti,'Source',"original_received_RAR_temporary_CRNTI_after_received_contention_match", ...
    'EncodingProfile',message.EncodingProfile,'MACRRCStandardsQualified',false);
end
