function setup=receivedNRRRCSetup(rarOwner,contentionOwner,stream)
% TS38.321 V18.8 5.1.5 + TS38.331 V18.8 5.3.3.4/9.2.1.
% Only original receiver owners install C-RNTI and the supported defaultSRB1.
% No gNB intended identity, authored success flags or transmitted Msg4 input.
err='sixgr:mac:ra:NRSetupReceiverAuthority';
assert(isa(rarOwner,'sixgr.phy.ra.RARReceiveWindow') && isscalar(rarOwner) && ...
    isa(contentionOwner,'sixgr.phy.ra.Msg4ReceiveWindow') && isscalar(contentionOwner) && ...
    isa(stream,'sixgr.truth.CoupledWaveformStream') && isscalar(stream) && ...
    rarOwner.Status=="matched" && contentionOwner.MAC.Status=="succeeded", ...
    err,'Require actual accepted RAR and successful UE contention receiver owners.');
rar=rarOwner.AcceptedResponse; last=contentionOwner.LastOutcome;
a=rarOwner.RAConfig;b=contentionOwner.RAConfig;
for name=["RunId","UEId","AttemptId","CellId","ServingCell"]
    assert(isequal(a.(name),b.(name)),err,'Received stages belong to different attempts/cells.');
end
assert(rar.Accepted && last.Status=="succeeded" && ...
    height(rar.Observation)==1 && height(last.Observation)==1 && ...
    rar.Observation.RARAccepted && last.Observation.DCICrcPass && last.Observation.PDSCHCrcPass && ...
    last.Observation.IdentityMatches && contentionOwner.MAC.IdentityMatches && ...
    isequaln(last.Observation,contentionOwner.Observations(end,:)) && ...
    isequaln(rar.Observation,rarOwner.Observations(end,:)), ...
    err,'Retain the original completed receiver decisions.');
fs=rar.Observation.SampleRateHz;endSample=last.Observation.ObservationEndSampleExclusive;
tc=double(sixgr.phy.frame.AbsoluteTime.TicksPerSecond)/fs;
assert(fs==stream.SampleRateHz && last.Observation.SampleRateHz==fs && tc==fix(tc) && ...
    rar.Observation.ObservationEndSampleExclusive<=last.Observation.ObservationStartSample && ...
    endSample<=stream.Events.NextSampleIndex && ...
    int64(endSample)*int64(tc)==contentionOwner.MAC.ResolutionTicks && ...
    contentionOwner.MAC.ResolutionTicks<=contentionOwner.MAC.ExpiryTicksExclusive, ...
    err,'Activation cannot precede its original received clock or exceed the contention window.');
rnti=rar.RAR.TemporaryCRNTI;
validateattributes(rnti,{'numeric'},{'scalar','real','finite','integer','>=',1,'<=',65522});
assert(b.TempCRNTI==rnti && contentionOwner.MAC.TemporaryCRNTI==rnti && ...
    last.PDCCH.CausalGrantDecodeOk && last.PDSCH.Ok,err,'Use the original received temporary identity.');
message=last.Message;
assert(message.EncodingProfile=="nr_rrc_access_base_srb1_uper_v1",err,'Private tagged access bytes cannot activate this NR profile.');
% Parse all original MAC bytes again. This guards the semantic adapter, not
% the radio outcome: only the original receiver can populate LastOutcome.
original=sixgr.mac.ra.parseNRInitialAccessMACPDU("DL",message.PayloadBytes);
assert(isequaln(original,message) && original.ContentionIdentity==contentionOwner.MAC.ExpectedIdentity && ...
    original.RRCSetup.SRB1LCID==1 && isnan(original.FinalCRNTI), ...
    err,'Use actual supported DL-CCCH Setup and MAC contention CE; no final-RNTI payload exists.');
% Join the original received bytes/captures to the already emitted cell Setup.
% This resolves a stable connection identity, never a new UE-indexed bearer.
rarCapture=stream.originalAccessReceiveCompletion("RAR",a.UEId,a.RunId,rar.Observation.AbsoluteSlot);
msg4Capture=stream.originalAccessReceiveCompletion("Contention",a.UEId,a.RunId,last.Observation.AbsoluteSlot);
assert(rar.OriginalObservationSHA256==rarCapture.PostRXSampleSHA256 && ...
    last.OriginalObservationSHA256==msg4Capture.PostRXSampleSHA256 && ...
    msg4Capture.EndSampleExclusive==endSample && msg4Capture.StartSample==last.Observation.ObservationStartSample,err, ...
    'Only actual original UE capture samples may admit the received Setup.');
issued=stream.completedCellMsg4Transmission(a.ServingCell,last.Observation.AbsoluteSlot,rnti);
assert(~isempty(fieldnames(issued)) && issued.ExecutionProof.RRCSetupSHA256==original.RRCSetupSHA256 && ...
    issued.ExecutionProof.Msg4MACPayloadSHA256==original.PayloadHash && ...
    isequal(issued.Prepared.Tx.Msg4.RRCCodecEvidence.Bytes,original.RRCCodecEvidence.Bytes),err, ...
    'Received Setup must be the exact original cell-issued message and full MAC TB.');
descriptor=sixgr.truth.resolveNRCellConnectionDescriptor(issued.Prepared,issued.ExecutionProof);
config=sixgr.truth.nrBaseSRB1ProtocolConfiguration(descriptor,"UL");
setup=struct('ContractVersion',"received_NR_base_SRB1_activation/v1", ...
    'RunId',string(a.RunId),'UEId',a.UEId,'AttemptId',a.AttemptId,'ServingCell',a.ServingCell, ...
    'RNTI',rnti,'RNTISource',"original_received_RAR_temporary_CRNTI_after_received_contention_match", ...
    'TransactionID',original.RRCSetup.TransactionID,'SRB1LCID',1, ...
    'ConnectionDescriptor',descriptor,'ConnectionID',descriptor.ConnectionID, ...
    'OriginalMsg4Proof',issued.ExecutionProof,'ReceiverObservationID',string(msg4Capture.ID), ...
    'ReceiverObservationSHA256',msg4Capture.PostRXSampleSHA256,'OriginalRARObservationSHA256',rarCapture.PostRXSampleSHA256, ...
    'OriginalContentionObservationSHA256',msg4Capture.PostRXSampleSHA256, ...
    'ProtocolConfiguration',config,'ReceivedMACPayloadSHA256',original.PayloadHash, ...
    'ReceivedRRCSetupSHA256',original.RRCSetupSHA256, ...
    'RARObservation',rar.Observation,'ContentionObservation',last.Observation, ...
    'AvailableAtSample',endSample,'SampleRateHz',fs,'PhysicalConfigurationEpoch',stream.Physical.ConfigurationEpoch, ...
    'EncodingProfile',original.EncodingProfile, ...
    'Source',"original_UE_RAR_and_contention_receivers_decoded_RRCSetup", ...
    'DefaultSRB1Reference',"TS38.331_V18.8.0_9.2.1", ...
    'MACRRCStandardsQualified',false,'NASRegistrationQualified',false,'DedicatedDRBInstalled',false);
setup.SHA256=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(setup))));
end
