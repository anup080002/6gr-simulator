function setup=receivedRRCSetup(message,pdcchOK,pdschOK,expectedContentionIdentity)
% Receive-side state for the bounded RRC codec, not a full NR RRC decoder.
% TS 38.331 5.3.3.4: SetupComplete uses the transaction received in Setup.
% Network intended configuration is deliberately not an input here.
identity=sixgr.mac.ra.receivedMsg4Identity( ...
    message,pdcchOK,pdschOK,expectedContentionIdentity);
assert(isequal(sixgr.util.structGet(message,'RRCSetupPresent',false),true), ...
    'sixgr:mac:ra:MissingReceivedRRCSetup','Accepted Msg4 must contain received RRCSetup.');
transaction=double(sixgr.util.structGet(message,'RRCSetup.TransactionID',NaN));
lcid=double(sixgr.util.structGet(message,'RRCSetup.SRB1LCID',NaN));
assert(isscalar(transaction) && isreal(transaction) && isfinite(transaction) && ...
    transaction==fix(transaction) && transaction>=0 && transaction<=3 && ...
    isscalar(lcid) && isreal(lcid) && isfinite(lcid) && ...
    lcid==fix(lcid) && lcid>=1 && lcid<=32, ...
    'sixgr:mac:ra:InvalidReceivedRRCSetup','Invalid received bounded transaction or logical-channel configuration.');
setup=struct('TransactionID',transaction,'SRB1LCID',lcid, ...
    'RNTI',identity.RNTI,'Source',"decoded_msg4_rrc_setup_after_contention_match", ...
    'EncodingProfile',identity.EncodingProfile,'MACRRCStandardsQualified',false);
end
