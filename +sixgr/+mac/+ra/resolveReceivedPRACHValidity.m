function out=resolveReceivedPRACHValidity(tree,mib,native)
%RESOLVERECEIVEDPRACHVALIDITY Derive RO validity from original decoded inputs.
% No host cfg, selected beam, TX bitmap, supplied validity mask or waveform
% enters this adapter. The original BCH context supplies the complete SSB
% candidate geometry and received radio-frame/half-frame anchor. Decoded
% SIB1 supplies the bitmap, periodicity, UL BWP and optional common TDD IE.
% TS38.213 V18.8.0 4.1/8.1/11.1 and TS38.331 V18.8.0 common IEs apply.
%
% This is decoded-input arithmetic, NOT delivery/generation authentication.
% The public BCH factory itself is not an execution attestation. Runtime
% callers must bind these inputs to their current UE/cell/received context.
% All joint-period decisions are preserved. The existing selection kernel
% can reject changing masks; this adapter must never collapse them.

assert(isa(mib,'sixgr.phy.broadcast.ReceivedMIBContext') && isscalar(mib), ...
    'sixgr:mac:ra:ReceivedValidityMIBRequired','Use an original immutable received MIB context.');
d=mib.Data;
assert(mib.SHA256==localHash(d) && islogical(d.GlobalCaptureEpochBound) && ...
    isscalar(d.GlobalCaptureEpochBound) && d.GlobalCaptureEpochBound, ...
    'sixgr:mac:ra:ReceivedValidityMIBRequired','The original capture epoch must be globally bound.');
g=d.ReceiverGeometry;
required=["SSBCase","SSBCyclicPrefix","SSBCandidateStartSymbolsWithinHalfFrame", ...
    "SSBSCSKHz","Lmax","FrequencyRange","OriginalTuningInputPaths","OriginalTuningInputValues"];
assert(all(isfield(g,required)) && localText(g.FrequencyRange)=="FR1" && ...
    ismember(g.Lmax,[4 8]),'sixgr:mac:ra:ReceivedValidityDomainUnsupported', ...
    'This inOneGroup adapter supports original licensed FR1 Lmax4/8 geometry only.');
duplex=localSpectrum(g);
caseToken=localText(g.SSBCase); ssbSCS=localNumber(g.SSBSCSKHz,[15 30]);
assert(any(caseToken==["A","B","C"]) && ((caseToken=="A")== (ssbSCS==15)) && ...
    localText(g.SSBCyclicPrefix)=="normal", ...
    'sixgr:mac:ra:ReceivedValidityGeometryMismatch','Unsupported original SSB Case/SCS/CP combination.');
spec=sixgr.phy.frame.AbsoluteTime.resolveNumerology(struct('SCSKHz',ssbSCS,'CyclicPrefix',"normal"));
candidates=g.SSBCandidateStartSymbolsWithinHalfFrame;
assert(isnumeric(candidates) && ~islogical(candidates) && isreal(candidates) && ...
    isrow(candidates) && numel(candidates)==g.Lmax && all(isfinite(candidates)) && ...
    all(candidates>=0 & candidates==fix(candidates)) && all(diff(candidates)>0) && ...
    all(candidates+4<=numel(spec.SymbolStartTicks)/2), ...
    'sixgr:mac:ra:ReceivedValidityGeometryMismatch','Retain the complete ordered original half-frame candidate geometry.');
frame=localInteger(d.AbsoluteFrameNumber,0,floor(flintmax/double(sixgr.phy.frame.AbsoluteTime.TicksPerFrame)));
half=localInteger(d.HalfFrame,0,1); sfn=localInteger(d.ReceivedSFN,0,1023);
receivedIndex=localInteger(d.SSBIndex,0,g.Lmax-1);
assert(mod(frame,1024)==sfn,'sixgr:mac:ra:ReceivedValidityGeometryMismatch', ...
    'Original received SFN and unwrapped radio frame disagree.');

assert(isstruct(tree) && isscalar(tree),'sixgr:mac:ra:ReceivedValiditySIB1Required', ...
    'Supply the original decoded SIB1 tree.');
try
    serving=tree.message.c1.systemInformationBlockType1.servingCellConfigCommon;
    ul=serving.uplinkConfigCommon.initialUplinkBWP;
    rach=ul.rach_ConfigCommon; generic=ul.genericParameters;
catch cause
    error('sixgr:mac:ra:ReceivedValiditySIB1Required','Missing original common SIB1 fields: %s',cause.message);
end
[~,treeEvidence]=sixgr.rrc.asn1.compareSIB1Trees(tree,tree);
treeHash=string(treeEvidence.RxTreeHash);
positions=serving.ssb_PositionsInBurst;
assert(isstruct(positions) && isscalar(positions) && ...
    isequal(string(fieldnames(positions)),"inOneGroup"), ...
    'sixgr:mac:ra:ReceivedValidityDomainUnsupported','Only original FR1 inOneGroup is supported.');
bitmap=localText(positions.inOneGroup);
assert(strlength(bitmap)==8 && all(ismember(char(bitmap),'01')), ...
    'sixgr:mac:ra:ReceivedValidityBitmapMismatch','Retain the eight ordered decoded bitmap bits.');
% For Lmax4, TS38.331 defines only the LEFTMOST four bits as valid.
active=find(char(extractBetween(bitmap,1,g.Lmax))=='1')-1;
assert(~isempty(active) && ismember(receivedIndex,active), ...
    'sixgr:mac:ra:ReceivedValidityBitmapMismatch','The original received SSB must belong to the decoded active population.');
tokens=["ms5","ms10","ms20","ms40","ms80","ms160"]; periods=[5 10 20 40 80 160];
periodToken=localText(serving.ssb_periodicityServingCell);
assert(any(periodToken==tokens),'sixgr:mac:ra:ReceivedValidityClockMismatch','Unsupported decoded SSB period.');
period=int64(periods(tokens==periodToken))*(sixgr.phy.frame.AbsoluteTime.TicksPerSecond/int64(1000));
frameTicks=sixgr.phy.frame.AbsoluteTime.TicksPerFrame;
burst=frameTicks*int64(frame)+(frameTicks/int64(2))*int64(half);
assert(double(burst)<=flintmax,'sixgr:mac:ra:ReceivedValidityClockMismatch','Original radio clock exceeds exact arithmetic range.');
phase=mod(burst,period);
starts=phase+spec.SymbolStartTicks(candidates(active+1)+1).';
ends=phase+spec.SymbolStartTicks(candidates(active+1)+5).';
assert(all(ends<=period),'sixgr:mac:ra:ReceivedValidityClockMismatch', ...
    'Original candidate supports must fit the decoded half-frame periodicity.');
intervals=table(active(:),starts(:),ends(:), ...
    'VariableNames',{'SSBIndex0','StartTicks','EndTicksExclusive'});
ssb=struct('Source',"decoded_common_configuration",'PeriodTicks',period, ...
    'SubcarrierSpacingKHz',ssbSCS,'Intervals',intervals);
scs=localSCS(generic.subcarrierSpacing);
% cyclicPrefix absence means normal CP in the original BWP ASN.1 IE; this
% is not a scenario/config fallback.
cp="normal"; if isfield(generic,'cyclicPrefix'), cp=localText(generic.cyclicPrefix); end
assert(any(cp==["normal","extended"]),'sixgr:mac:ra:ReceivedValidityClockMismatch','Invalid decoded UL BWP CP.');
msg1SCSSource=localNativeIdentity(native,rach,scs,cp,duplex);
tdd=[]; present=isfield(serving,'tdd_UL_DL_ConfigurationCommon');
if present
    tdd=serving.tdd_UL_DL_ConfigurationCommon;
    resolved=sixgr.rrc.asn1.resolveTDDCommonRuntime(tdd,scs,cp,"FR1");
    assert(resolved.Present,'sixgr:mac:ra:ReceivedValidityClockMismatch','Present decoded TDD IE must not be an absent marker.');
end
common=struct('Source',"decoded_common_configuration",'CarrierCyclicPrefix',cp, ...
    'TDDCommonIE',tdd,'Procedure',"type1_single_preamble",'ChannelAccessMode',"not_provided");
evaluation=sixgr.phy.ra.resolvePRACHCandidateValidity(native,common,ssb);
out=struct('ContractVersion',"received_prach_candidate_validity_input/v1", ...
    'AdapterContractVersion',"decoded_received_prach_validity/v1", ...
    'Scope',"decoded_input_clock_evaluation_not_runtime_authentication_or_PHY_execution", ...
    'RuntimeAuthorityVerified',false,'PHYExecutionPerformed',false, ...
    'NativeInputIndependentlyAuthenticated',false, ...
    'MIBContextSHA256',mib.SHA256,'SIB1TreeSHA256',treeHash, ...
    'NativeResolutionSHA256',evaluation.NativeResolutionSHA256, ...
    'TDDCommonPresent',evaluation.TDDCommonPresent,'TDDCommonSHA256',evaluation.TDDCommonSHA256, ...
    'EvaluatedPeriodTicks',evaluation.EvaluatedPeriodTicks, ...
    'CandidateSupport',evaluation.CandidateSupport,'RepeatedValidity',evaluation.RepeatedValidity, ...
    'DecisionReasons',evaluation.DecisionReasons,'Evaluation',evaluation, ...
    'OriginalReceivedSSBGeometry',g,'OriginalDecodedSSBBitmap',bitmap, ...
    'OriginalDecodedSSBPeriod',periodToken,'ReceivedBurstRadioTicks',burst, ...
    'DecodedMsg1SCSSource',msg1SCSSource, ...
    'SSBBurstPhaseTicks',phase,'SSBIntervals',intervals, ...
    'OriginalReceivedFrameOriginSample',d.ReceivedFrameOriginSample, ...
    'ClockScope',"radio_frame_zero_Tc_not_receiver_sample_or_propagation_phase", ...
    'SelectionSupportsAllPeriods',all(evaluation.RepeatedValidity==evaluation.RepeatedValidity(:,1),'all'));
out.ReceiptSHA256=localHash(out);
end

function duplex=localSpectrum(g)
paths=g.OriginalTuningInputPaths; values=g.OriginalTuningInputValues;
assert(isstring(paths) && isvector(paths) && iscell(values) && numel(paths)==numel(values) && ...
    numel(unique(paths))==numel(paths),'sixgr:mac:ra:ReceivedValidityGeometryMismatch','Malformed original tuning input ledger.');
spectrum="";
for k=1:numel(paths)
    value=values{k};
    if isstruct(value) && isscalar(value) && isequal(fieldnames(value),{'OriginalPathAbsent'}) && ...
            isequal(value.OriginalPathAbsent,true)
        continue;
    end
    if any(paths(k)==["initial_access.shared_spectrum","frequency.shared_spectrum"])
        assert(islogical(value) && isscalar(value) && ~value, ...
            'sixgr:mac:ra:ReceivedValidityDomainUnsupported','Shared-spectrum/discovery-window SSB remapping is not implemented here.');
    elseif any(paths(k)==["initial_access.spectrum","frequency.spectrum"])
        token=localText(value); if strlength(token)==0, continue; end
        assert(any(token==["paired","unpaired"]),'sixgr:mac:ra:ReceivedValidityDomainUnsupported', ...
            'Use the original explicit licensed paired/unpaired spectrum context.');
        assert(strlength(spectrum)==0 || spectrum==token, ...
            'sixgr:mac:ra:ReceivedValidityGeometryMismatch','Original spectrum aliases contradict each other.');
        spectrum=token;
    end
end
assert(strlength(spectrum)>0,'sixgr:mac:ra:ReceivedValidityDomainUnsupported', ...
    'Original spectrum identity is required; absent TDD does not imply paired spectrum.');
duplex="FDD"; if spectrum=="unpaired", duplex="TDD"; end
end

function source=localNativeIdentity(n,r,scs,cp,duplex)
fields=["ContractVersion","FrequencyRange","DuplexMode","ConfigurationIndex", ...
    "CarrierSubcarrierSpacingKHz","CarrierCyclicPrefix","PRACHSubcarrierSpacingKHz", ...
    "Format","RestrictedSet","ZeroCorrelationZone","Msg1FDM","Msg1FrequencyStart"];
assert(isstruct(n) && isscalar(n) && all(isfield(n,fields)) && ...
    localText(n.ContractVersion)=="sixgr_prach_occasion_release18/v1", ...
    'sixgr:mac:ra:ReceivedValidityNativeRequired','Require the original native resolution including carrier CP provenance.');
[psc,source]=sixgr.mac.ra.resolveDecodedPRACHSubcarrierSpacing(r);
tokens=["one","two","four","eight"]; values=[1 2 4 8]; fdm=localText(r.msg1FDM);
assert(any(fdm==tokens),'sixgr:mac:ra:ReceivedValidityNativeMismatch','Invalid decoded msg1-FDM.');
assert(localText(n.FrequencyRange)=="FR1" && localText(n.DuplexMode)==duplex && ...
    n.ConfigurationIndex==localInteger(r.configurationIndex,0,262) && ...
    n.CarrierSubcarrierSpacingKHz==scs && localText(n.CarrierCyclicPrefix)==cp && ...
    n.PRACHSubcarrierSpacingKHz==psc && localText(n.Format)==localText(r.preambleFormat) && ...
    localText(n.RestrictedSet)==localText(r.restrictedSet) && ...
    n.ZeroCorrelationZone==localInteger(r.zeroCorrelationZoneConfig,0,15) && ...
    n.Msg1FDM==values(tokens==fdm) && n.Msg1FrequencyStart==localInteger(r.msg1FrequencyStart,0,flintmax), ...
    'sixgr:mac:ra:ReceivedValidityNativeMismatch','Original native RO geometry disagrees with decoded RACH/UL BWP or frozen spectrum.');
end
function v=localInteger(v,lo,hi)
assert(isnumeric(v) && ~islogical(v) && isreal(v) && isscalar(v) && isfinite(v) && ...
    v==fix(v) && v>=lo && v<=hi,'sixgr:mac:ra:ReceivedValidityInvalidOperand','Require an original finite integer.');
v=double(v);
end
function v=localNumber(v,allowed)
assert(isnumeric(v) && ~islogical(v) && isreal(v) && isscalar(v) && isfinite(v) && ismember(v,allowed), ...
    'sixgr:mac:ra:ReceivedValidityInvalidOperand','Unsupported original numeric operand.');
v=double(v);
end
function s=localText(s)
assert((isstring(s) && isscalar(s) && ~ismissing(s)) || (ischar(s) && isrow(s)), ...
    'sixgr:mac:ra:ReceivedValidityInvalidOperand','Require original scalar text.');
s=string(s);
end
function scs=localSCS(token)
tokens=["kHz15","kHz30","kHz60","kHz120"]; values=[15 30 60 120]; token=localText(token);
assert(any(token==tokens),'sixgr:mac:ra:ReceivedValidityClockMismatch','Unsupported original UL BWP SCS.');
scs=values(tokens==token);
end
function h=localHash(value)
h=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(value))));
end
