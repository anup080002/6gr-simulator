function association = resolveSSBPRACHAssociation(resolution, ssbIndices, ssbsPerRO, cbPreamblesPerSSB, totalPreambles, validOccasions)
%RESOLVESSBPRACHASSOCIATION Type-1 CBRA SSB/resource mapping, not a receiver.
% TS 38.213 V18.8.0 clause 8.1 and Table 8.1-1. Inputs must come from the
% installed common configuration and the canonical occasion/validity owner.
% This function does NOT decide TDD/SSB-gap validity, select a preamble,
% apply a dedicated mask, or implement MsgA/CFRA/repetition partitions.
% The initial supported calendar has a validity pattern repeating in every
% PRACH configuration period. A longer TDD/calendar pattern fails explicitly.

assert(isstruct(resolution) && isscalar(resolution), ...
    'sixgr:mac:ra:InvalidAssociationTiming','Require one canonical PRACH resolution.');
required={'BasePeriodFrames','PeriodFrames','BasePeriodCarrierSlots', ...
    'PeriodCarrierSlots','BasePeriodPRACHSlots','PeriodPRACHSlots','Occasions'};
assert(all(isfield(resolution,required)), ...
    'sixgr:mac:ra:InvalidAssociationTiming','Missing original PRACH repetition operands.');
for f=string(required(1:6))
    localInteger(resolution.(f),1,flintmax,'repetition operand');
end
baseFrames=double(resolution.BasePeriodFrames);
baseSlots=double(resolution.BasePeriodCarrierSlots);
assert(ismember(baseFrames,[1 2 4 8 16]) && mod(baseSlots,baseFrames)==0, ...
    'sixgr:mac:ra:InvalidAssociationTiming', ...
    'Table 8.1-1 requires 10/20/40/80/160-ms PRACH periods and an exact carrier clock.');
assert(resolution.PeriodFrames==baseFrames && ...
    resolution.PeriodCarrierSlots==baseSlots && ...
    resolution.PeriodPRACHSlots==resolution.BasePeriodPRACHSlots, ...
    'sixgr:mac:ra:AssociationPatternNotImplemented', ...
    'A validity calendar longer than the PRACH configuration period requires its own association-pattern implementation.');
slotsPerFrame=baseSlots/baseFrames;
assert(ismember(slotsPerFrame,[10 20 40 80 160 320 640]), ...
    'sixgr:mac:ra:InvalidAssociationTiming','Require a supported exact NR carrier slot clock.');
assert(isnumeric(ssbIndices) && isreal(ssbIndices) && isvector(ssbIndices) && ...
    ~isempty(ssbIndices) && all(isfinite(ssbIndices)) && ...
    all(ssbIndices==fix(ssbIndices)) && all(ssbIndices>=0 & ssbIndices<=63) && ...
    numel(unique(ssbIndices))==numel(ssbIndices), ...
    'sixgr:mac:ra:InvalidAssociationSSBs','Require unique active zero-based SSB indices from the installed bitmap.');
ssbIndices=sort(double(ssbIndices(:)));
assert(isnumeric(ssbsPerRO) && isreal(ssbsPerRO) && isscalar(ssbsPerRO) && ...
    ismember(ssbsPerRO,[1/8 1/4 1/2 1 2 4 8 16]), ...
    'sixgr:mac:ra:InvalidSSBsPerRO','SSBs per RO must be an allowed ssb-perRACH choice.');
localInteger(totalPreambles,1,64,'totalNumberOfRA-Preambles');
localInteger(cbPreamblesPerSSB,1,64,'CB preambles per SSB');
% RACH-ConfigCommon CHOICE domain, also enforced by the installed SIB1
% ASN.1 codec: N<=1 and N=2 use n4-step enums; N>=4 uses integer ranges.
if ssbsPerRO<=2
    allowedCB=4:4:(64/max(1,ssbsPerRO));
else
    allowedCB=1:(64/ssbsPerRO);
end
assert(ismember(cbPreamblesPerSSB,allowedCB), ...
    'sixgr:mac:ra:InvalidAssociationPreambleChoice', ...
    'CB-preamble count cannot be represented by this SSBs-per-RO RRC choice.');
partitionsPerRO=max(1,double(ssbsPerRO));
rosPerSSB=max(1,1/double(ssbsPerRO));
assert(mod(totalPreambles,partitionsPerRO)==0 && ...
    cbPreamblesPerSSB<=totalPreambles/partitionsPerRO, ...
    'sixgr:mac:ra:InvalidAssociationPreambles', ...
    'Total preambles must divide into N equal partitions; each CB population must fit its partition.');

original=resolution.Occasions;
coordinates=["Ordinal","Frame","AbsoluteSlot","SlotWithinFrame", ...
    "PRACHSlot","ActivePRACHSlot","TimeIndex","FrequencyIndex"];
assert(istable(original) && ~isempty(original) && ...
    all(ismember(coordinates,string(original.Properties.VariableNames))), ...
    'sixgr:mac:ra:InvalidAssociationOccasions','Require original zero-based native occasion coordinates.');
for f=coordinates
    v=original.(f);
    assert(isnumeric(v) && isreal(v) && iscolumn(v) && all(isfinite(v)) && ...
        all(v==fix(v)) && all(v>=0), ...
        'sixgr:mac:ra:InvalidAssociationOccasions','Occasion coordinates must be nonnegative integers.');
end
assert(all(original.AbsoluteSlot<baseSlots) && ...
    all(original.PRACHSlot<resolution.BasePeriodPRACHSlots) && ...
    all(original.Frame==floor(original.AbsoluteSlot/slotsPerFrame)) && ...
    all(original.SlotWithinFrame==mod(original.AbsoluteSlot,slotsPerFrame)), ...
    'sixgr:mac:ra:InvalidAssociationOccasions','Native occasion clocks must agree within the original configuration period.');
assert((isnumeric(validOccasions)||islogical(validOccasions)) && ...
    isreal(validOccasions) && isvector(validOccasions) && ...
    numel(validOccasions)==height(original) && all(ismember(validOccasions,[0 1])), ...
    'sixgr:mac:ra:MissingAssociationValidity', ...
    'Supply an explicit validity decision for every original occasion; absence is not validity.');
keys=original{:,{'PRACHSlot','ActivePRACHSlot','TimeIndex','FrequencyIndex'}};
assert(size(unique(keys,'rows'),1)==height(original) && ...
    numel(unique(original.Ordinal))==height(original), ...
    'sixgr:mac:ra:DuplicateAssociationOccasion','Duplicate native RO identity cannot be counted twice.');
assert(isequal(sort(double(original.Ordinal)),(1:height(original)).'), ...
    'sixgr:mac:ra:InvalidAssociationOrdinal', ...
    'Native ordinal identities must be a permutation of 1:numberOfOriginalOccasions before period translation.');
validRows=find(logical(validOccasions(:)));
[~,order]=sortrows(keys(validRows,:),[1 2 3 4]);
validRows=validRows(order);
assert(~isempty(validRows),'sixgr:mac:ra:NoValidAssociationOccasion', ...
    'No valid PRACH occasion is available for SSB association.');

% Table 8.1-1 periods are counts of the native configuration period. Use
% complete SSB mapping cycles only; never fill the trailing partial cycle.
allowedPeriods=2.^(0:log2(16/baseFrames));
requiredROs=ceil(numel(ssbIndices)/partitionsPerRO)*rosPerSSB;
periodCount=allowedPeriods(find(numel(validRows)*allowedPeriods>=requiredROs,1));
assert(~isempty(periodCount),'sixgr:mac:ra:SSBAssociationCoverageImpossible', ...
    'All active SSBs cannot be mapped within an allowed association period.');
roCount=numel(validRows)*periodCount;
if ssbsPerRO<1
    cycles=floor(roCount/(numel(ssbIndices)*rosPerSSB));
    usedROs=cycles*numel(ssbIndices)*rosPerSSB;
    roIndex0=(0:usedROs-1).';
    ssbPosition=mod(floor(roIndex0/rosPerSSB),numel(ssbIndices))+1;
    cycleIndex0=floor(roIndex0/(numel(ssbIndices)*rosPerSSB));
    partitionIndex0=zeros(size(roIndex0));
    unusedPartitions=roCount-usedROs;
else
    capacity=roCount*partitionsPerRO;
    cycles=floor(capacity/numel(ssbIndices));
    entryIndex0=(0:cycles*numel(ssbIndices)-1).';
    roIndex0=floor(entryIndex0/partitionsPerRO);
    partitionIndex0=mod(entryIndex0,partitionsPerRO);
    ssbPosition=mod(entryIndex0,numel(ssbIndices))+1;
    cycleIndex0=floor(entryIndex0/numel(ssbIndices));
    unusedPartitions=capacity-numel(entryIndex0);
end
periodIndex0=floor(roIndex0/numel(validRows));
sourceRows=validRows(mod(roIndex0,numel(validRows))+1);
mapping=original(sourceRows,:);
mapping.SourceOccasionRow=sourceRows;
mapping.ConfigurationPeriodIndex0=periodIndex0;
mapping.ROIndexWithinAssociation0=roIndex0;
mapping.SSBMappingCycleIndex0=cycleIndex0;
mapping.SSBIndex0=ssbIndices(ssbPosition);
mapping.PreamblePartitionIndex0=partitionIndex0;
mapping.CBPreambleStart0=partitionIndex0*(double(totalPreambles)/partitionsPerRO);
mapping.CBPreambleCount=repmat(double(cbPreamblesPerSSB),height(mapping),1);
% Preserve source identity separately when translating coordinates into the
% association period. SlotWithinFrame/ActivePRACHSlot/TimeIndex are unchanged.
mapping.SourceOccasionOrdinal=mapping.Ordinal;
mapping.Ordinal=double(mapping.Ordinal)+periodIndex0*height(original);
mapping.Frame=double(mapping.Frame)+periodIndex0*baseFrames;
mapping.AbsoluteSlot=double(mapping.AbsoluteSlot)+periodIndex0*baseSlots;
mapping.PRACHSlot=double(mapping.PRACHSlot)+ ...
    periodIndex0*double(resolution.BasePeriodPRACHSlots);
% Additional waveform sample/tick fields remain original-period operands.
% Do not publish them beside translated coordinates with ambiguous clocks.
mapping=mapping(:,cellstr([coordinates, "SourceOccasionRow", ...
    "SourceOccasionOrdinal","ConfigurationPeriodIndex0", ...
    "ROIndexWithinAssociation0","SSBMappingCycleIndex0","SSBIndex0", ...
    "PreamblePartitionIndex0","CBPreambleStart0","CBPreambleCount"]));
association=struct('ContractVersion',"type1_cbra_ssb_ro_association/v1", ...
    'Standard',"3GPP TS 38.213 V18.8.0 clause 8.1, Table 8.1-1", ...
    'Scope',"configured_resource_association_not_transmission_or_reception", ...
    'IndexConvention',"zero_based_radio_coordinates_one_based_source_rows", ...
    'ValidityScope',"caller_supplied_complete_repeating_configuration_period", ...
    'OriginalOccasions',original,'OriginalValidityMask',logical(validOccasions(:)), ...
    'ActiveSSBIndices0',ssbIndices,'SSBsPerRO',double(ssbsPerRO), ...
    'CBPreamblesPerSSB',double(cbPreamblesPerSSB), ...
    'TotalPreambles',double(totalPreambles), ...
    'ConfigurationPeriodFrames',baseFrames, ...
    'AssociationPeriodConfigurationCount',periodCount, ...
    'AssociationPeriodFrames',periodCount*baseFrames, ...
    'AssociationPeriodCarrierSlots',periodCount*baseSlots, ...
    'CompleteMappingCycles',cycles,'UnassociatedPartitionCount',unusedPartitions, ...
    'Mapping',mapping);
end

function localInteger(value,minimum,maximum,label)
assert(isnumeric(value) && isreal(value) && isscalar(value) && isfinite(value) && ...
    value==fix(value) && value>=minimum && value<=maximum, ...
    'sixgr:mac:ra:InvalidAssociationOperand','Invalid integer %s.',label);
end
