classdef NRRRCSetupAttemptState
    % One initial NR RRC attempt, independent of its MAC PRACH retry count.
    % TS38.331 V18.8.0 5.3.3.2/.3/.4/.7. Reset execution is a separate owner.
    properties (SetAccess=private)
        Context struct
        Policy struct
        CommonIdentity struct
        Request struct
        StartSample double
        ExpirySampleExclusive double
        T300Milliseconds double
        Status string = "waiting_setup"
        MACAttemptRunIDs string = strings(0,1)
        ReceivedSetup struct = struct()
        StopSample double = NaN
        ExpiryReceipt struct = struct()
        ResetReceipt struct = struct()
    end
    methods
        function obj=NRRRCSetupAttemptState(policy,common,recovery,context,randomStream)
            id='sixgr:rrc:InitialAttemptAuthority';
            assert(isstruct(policy)&&isscalar(policy)&&policy.Enabled && ...
                policy.EncodingProfile=="nr_rrc_access_base_srb1_uper_v1",id, ...
                'An explicit supported NR policy is required.');
            fields={'RunID','UEIndex','ServingCell','ConfigurationEpoch','SampleRateHz','StartSample'};
            assert(isstruct(context)&&isscalar(context)&&all(isfield(context,fields)),id, ...
                'Bind the original UE, cell and sample-clock epoch.');
            for name=["UEIndex","ServingCell","ConfigurationEpoch","StartSample"]
                validateattributes(context.(name),{'numeric'},{'scalar','real','finite','integer','nonnegative'});
            end
            validateattributes(context.SampleRateHz,{'numeric'},{'scalar','real','finite','positive'});
            assert(context.UEIndex>=1 && context.ServingCell>=1 && strlength(string(context.RunID))>0,id, ...
                'Require a concrete execution and UE identity.');
            assert(isa(randomStream,'RandStream')&&isscalar(randomStream),id, ...
                'Use an explicitly owned random stream, not global RNG or a UE ordinal identity.');
            for name=["StrictOk","DCICrcPass","DLSCHCrcPass","SIB1ASN1DecodeOk","SIB1SemanticValid"]
                assert(isfield(recovery,name)&&isequal(recovery.(name),true),id, ...
                    'Start only after the original essential-SI receive decision.');
            end
            tree=recovery.SIB1RxTree;
            for digest=[string(common.PayloadHash),string(common.TreeHash), ...
                    string(recovery.SIB1PayloadHashRx),string(recovery.SIB1RxTreeHash)]
                assert(~isempty(regexp(char(digest),'^[0-9a-fA-F]{64}$','once')),id, ...
                    'Retain original nonempty SI payload/tree digests.');
            end
            [~,comparison]=sixgr.rrc.asn1.compareSIB1Trees(tree,tree);
            assert(common.Source=="decoded_sib1" && common.ServingCell==context.ServingCell && ...
                string(common.PayloadHash)==string(recovery.SIB1PayloadHashRx) && ...
                string(common.TreeHash)==string(recovery.SIB1RxTreeHash) && ...
                string(common.TreeHash)==string(comparison.RxTreeHash) && ...
                common.ConfigurationEpoch==recovery.ReferenceConfigurationEpoch && ...
                recovery.MeasurementClockEpoch==context.ConfigurationEpoch && ...
                recovery.OriginalServingCell==context.ServingCell && ...
                recovery.ReceivedSIB1AvailableAtSample<=context.StartSample,id, ...
                'T300 must retain the original delivered SI, cell and physical clock.');
            timers=tree.message.c1.systemInformationBlockType1.ue_TimersAndConstants;
            assert(isfield(common,'UETimersAndConstants')&&isequaln(common.UETimersAndConstants,timers), ...
                id,'Installed UE timers must match the exact original decoded IE.');
            tag=string(timers.t300);
            allowed=[100 200 300 400 600 1000 1500 2000];
            hit=find(tag=="ms"+string(allowed));
            assert(isscalar(hit),id,'This initial-access profile requires a supported received base T300.');
            duration=allowed(hit)*context.SampleRateHz/1000;
            assert(duration==fix(duration)&&duration>0&&context.StartSample+duration<=flintmax,id, ...
                'Retain an exact integer sample deadline; never round the received timer.');
            value=randi(randomStream,[0 2^39-1],1,1);
            obj.Request=sixgr.mac.ra.buildNRMsg3Payload("randomValue",value,policy.EstablishmentCause);
            obj.Context=context;obj.Policy=policy;
            obj.CommonIdentity=struct('PayloadHash',string(common.PayloadHash),'TreeHash',string(common.TreeHash), ...
                'AcquisitionConfigurationEpoch',common.ConfigurationEpoch,'T300',tag, ...
                'AvailableAtSample',recovery.ReceivedSIB1AvailableAtSample);
            obj.StartSample=context.StartSample;obj.T300Milliseconds=allowed(hit);
            obj.ExpirySampleExclusive=context.StartSample+duration;
        end
        function obj=bindMACAttempt(obj,ra,nowSample)
            id='sixgr:rrc:InitialAttemptAuthority';
            assert(obj.Status=="waiting_setup" && nowSample>=obj.StartSample && ...
                nowSample<obj.ExpirySampleExclusive && ra.UEId==obj.Context.UEIndex && ...
                ra.ServingCell==obj.Context.ServingCell,id,'A MAC retry must remain inside its original RRC attempt.');
            key=string(ra.RunId);
            assert(strlength(key)>0&&~any(obj.MACAttemptRunIDs==key),id,'Bind each original MAC attempt once.');
            obj.MACAttemptRunIDs(end+1,1)=key;
        end
        function [obj,setup]=receiveSetup(obj,rarOwner,contentionOwner,stream)
            id='sixgr:rrc:InitialAttemptAuthority';
            assert(obj.Status=="waiting_setup",id,'Only the current RRC attempt accepts Setup.');
            setup=sixgr.mac.ra.receivedNRRRCSetup(rarOwner,contentionOwner,stream);
            assert(any(obj.MACAttemptRunIDs==setup.RunId) && setup.UEId==obj.Context.UEIndex && ...
                setup.ServingCell==obj.Context.ServingCell && ...
                setup.PhysicalConfigurationEpoch==obj.Context.ConfigurationEpoch && ...
                setup.SampleRateHz==obj.Context.SampleRateHz && ...
                setup.AvailableAtSample>=obj.StartSample && setup.AvailableAtSample<=obj.ExpirySampleExclusive && ...
                contentionOwner.MAC.ExpectedIdentity==obj.Request.ContentionIdentity,id, ...
                'Received Setup must resolve this original request before its T300 deadline.');
            obj.Status="ue_connected_setup_complete_pending";
            obj.ReceivedSetup=setup;obj.StopSample=setup.AvailableAtSample;
        end
        function [obj,receipt]=expire(obj,nowSample)
            id='sixgr:rrc:InitialAttemptAuthority';
            assert(nowSample==obj.ExpirySampleExclusive,id,'Dispatch T300 on its exact original sample deadline.');
            if obj.Status=="ue_connected_setup_complete_pending"
                receipt=struct('Expired',false,'Reason',"stopped_by_original_received_RRCSetup", ...
                    'StopSample',obj.StopSample,'ResetExecuted',false);
                return;
            end
            assert(obj.Status=="waiting_setup",id,'T300 expiry is delivered once.');
            obj.Status="t300_expired_pending_reset";
            receipt=struct('Expired',true,'Reason',"original_received_T300_deadline", ...
                'Context',obj.Context,'ExpirySample',nowSample,'SampleRateHz',obj.Context.SampleRateHz, ...
                'CommonIdentity',obj.CommonIdentity,'RequestSHA256',obj.Request.RRCSetupRequestSHA256, ...
                'RequiredActions',["reset_UE_MAC","release_UE_MAC_configuration","reestablish_existing_RLC"], ...
                'ResetExecuted',false,'ApplicationBytesDropped',0);
            obj.ExpiryReceipt=receipt;
        end
        function obj=resetCompleted(obj,receipt)
            id='sixgr:rrc:InitialAttemptAuthority';
            assert(obj.Status=="t300_expired_pending_reset" && isstruct(receipt)&&isscalar(receipt)&& ...
                all(isfield(receipt,{'ContractVersion','Context','ResetExecuted','ResetSample', ...
                'RequestSHA256','ExistingRLCBearerCount','ExistingRLCReestablishmentRequired', ...
                'ApplicationBytesDropped','ReceivedSystemInformationPreserved','GNBCellResponsesCancelled', ...
                'UpperLayerIndication','SHA256'})) && ...
                receipt.ContractVersion=="initial_NR_T300_MAC_reset/v1" && ...
                isequaln(receipt.Context,obj.Context)&&isequal(receipt.ResetExecuted,true)&& ...
                receipt.ResetSample==obj.ExpirySampleExclusive && ...
                receipt.RequestSHA256==obj.Request.RRCSetupRequestSHA256 && ...
                receipt.ExistingRLCBearerCount==0&&~receipt.ExistingRLCReestablishmentRequired && ...
                receipt.ApplicationBytesDropped==0&&receipt.ReceivedSystemInformationPreserved && ...
                ~receipt.GNBCellResponsesCancelled && ...
                receipt.UpperLayerIndication=="initial_RRC_establishment_failure_T300",id, ...
                'Complete only the original initial-establishment reset transaction.');
            assert(receipt.SHA256==string(sixgr.util.sha256Hex(jsonencode(rmfield(receipt,'SHA256')))), ...
                id,'An expiry is not proof of executed reset.');
            obj.ResetReceipt=receipt;obj.Status="failed_upper_layer_notified";
        end
    end
end
