function common = resolveReceivedCommonMIBConfiguration(cfg,recovery)
% Receiver-owned RAR reference: original BCH plus its accepted SI, not YAML MIB.
% This projects retained decoder evidence. It performs no waveform reception.
common=struct();
assert(isstruct(recovery) && isscalar(recovery), ...
    'sixgr:mac:ra:InvalidReceivedCommonMIB','Require one original received SI result.');
separate=isfield(recovery,'PriorBCHContextSHA256');
hasBinding=isfield(recovery,'ReceivedMIBBinding') && ~isempty(recovery.ReceivedMIBBinding);
if separate && ~hasBinding
    error('sixgr:mac:ra:MissingReceivedMIBBinding', ...
        'SI-only common configuration requires its original delivered BCH binding.');
end
if hasBinding
    b=recovery.ReceivedMIBBinding;
    sixgr.truth.ReceivedMIBDelivery.validate(b,true);
    b.Context.validate(cfg);
    d=b.Context.Data;
    for flag=["StrictOk","DCICrcPass","DLSCHCrcPass","SIB1ASN1DecodeOk","SIB1SemanticValid"]
        assert(localTrue(recovery,flag),'sixgr:mac:ra:InvalidReceivedCommonMIB', ...
            'Only accepted original SI may install the RAR common reference.');
    end
    required={'ReceivedMIBGenerationID','ReceivedMIBDeliverySHA256', ...
        'ReferenceConfigurationEpoch','MeasurementClockEpoch','OriginalServingCell'};
    assert(all(isfield(recovery,required)) && ...
        isequal(recovery.ReceivedMIBGenerationID,b.GenerationID) && ...
        isequal(recovery.ReceivedMIBDeliverySHA256,b.DeliverySHA256) && ...
        isequal(recovery.ReferenceConfigurationEpoch,b.AcquisitionConfigurationEpoch) && ...
        isequal(recovery.MeasurementClockEpoch,b.PhysicalConfigurationEpoch) && ...
        isequal(recovery.OriginalServingCell,b.ServingCell), ...
        'sixgr:mac:ra:ReceivedCommonMIBIdentityMismatch', ...
        'The received SI and original delivered MIB must retain one acquisition/cell/epoch.');
    if separate
        required={'NewBCHReceptionAttempted','PriorReceivedNCellID','PriorReceivedSSBIndex', ...
            'SIB1CaptureStartSample','SIB1AvailableCaptureSamples','SampleRateHz','ReceivedSIB1AvailableAtSample'};
        assert(all(isfield(recovery,required)) && ...
            isequal(recovery.NewBCHReceptionAttempted,false) && ...
            isequal(recovery.PriorBCHContextSHA256,b.ContextSHA256) && ...
            isequal(recovery.PriorReceivedNCellID,d.NCellID) && ...
            isequal(recovery.PriorReceivedSSBIndex,d.SSBIndex), ...
            'sixgr:mac:ra:ReceivedCommonMIBIdentityMismatch', ...
            'SI-only reception must retain its actual prior BCH identity, not same-result BCH flags.');
        first=localInteger(recovery.SIB1CaptureStartSample,0);
        count=localInteger(recovery.SIB1AvailableCaptureSamples,1);
        available=localInteger(recovery.ReceivedSIB1AvailableAtSample,0);
        assert(first+count<=flintmax && first>=b.DeliveredAvailableSample && ...
            first+count<=available && isequal(recovery.SampleRateHz,b.SampleRateHz), ...
            'sixgr:mac:ra:ReceivedCommonMIBAvailabilityMismatch', ...
            'Retained MIB must be delivered before later SI; SI must complete before installation.');
    else
        assert(localTrue(recovery,'MIBDecoded') && localTrue(recovery,'BCHCrcPass') && ...
            isequal(recovery.MIBDMRSTypeAPosition,d.MIB.DMRSTypeAPosition), ...
            'sixgr:mac:ra:ReceivedCommonMIBIdentityMismatch', ...
            'Combined receiver MIB fields must agree with the original BCH binding.');
    end
    % A selected-beam timing reference can differ from the acquisition beam,
    % but it cannot replace the MIB generation which authorized received SI.
    if isfield(cfg,'SharedRATimingBinding')
        t=cfg.SharedRATimingBinding;
        sixgr.truth.ReceivedSSBTimingDelivery.validate(t,true);
        assert(t.AcquisitionGenerationID==b.GenerationID && ...
            t.OriginalBCHBinding.UEIndex==b.UEIndex && ...
            t.OriginalBCHBinding.ServingCell==b.ServingCell, ...
            'sixgr:mac:ra:ReceivedCommonMIBIdentityMismatch', ...
            'Current RA timing and installed SI must belong to the same acquisition generation.');
    end
    % Resolve only from original received MIB bits plus frozen receiver tuning.
    % No configured MIB field or selected TX monitoring ordinal is authority.
    [type0,~]=sixgr.phy.broadcast.deriveType0PDCCHFromMIB( ...
        sixgr.phy.grid.makeCarrier(cfg),cfg,d.MIB);
    assert(localTrue(recovery,'CORESET0Present') && ...
        isequal(recovery.CORESET0NumRB,double(type0.CORESET0.NumRB)) && ...
        isequal(recovery.CORESET0RBStart,double(type0.CORESET0.RBStart)), ...
        'sixgr:mac:ra:ReceivedCommonMIBType0Mismatch', ...
        'Accepted SI CORESET0 must match its original received MIB and receiver tuning.');
    if separate || isfield(recovery,'PDCCHConfigSIB1')
        assert(isfield(recovery,'PDCCHConfigSIB1') && ...
            isequal(recovery.PDCCHConfigSIB1,double(d.MIB.PDCCHConfigSIB1)), ...
            'sixgr:mac:ra:ReceivedCommonMIBType0Mismatch','SI control context must match received MIB bits.');
    end
    common=struct('Source',"decoded_mib_bch_transport_block", ...
        'ReceptionRelationship',"retained_original_delivered_BCH_for_received_SI", ...
        'DMRSTypeAPosition',double(d.MIB.DMRSTypeAPosition),'CORESET0Present',true, ...
        'CORESET0NumRB',double(type0.CORESET0.NumRB),'CORESET0RBStart',double(type0.CORESET0.RBStart), ...
        'NCellID',d.NCellID,'SSBIndex',d.SSBIndex,'UEIndex',b.UEIndex,'ServingCell',b.ServingCell, ...
        'ReceivedMIBContextSHA256',b.ContextSHA256,'ReceivedMIBGenerationID',b.GenerationID, ...
        'ReceivedMIBDeliverySHA256',b.DeliverySHA256, ...
        'BCHTransportBlockHash',string(d.MIB.TransportBlockHash), ...
        'MIBAvailableAtSample',b.DeliveredAvailableSample, ...
        'ConfigurationEpoch',b.AcquisitionConfigurationEpoch,'PhysicalConfigurationEpoch',b.PhysicalConfigurationEpoch);
elseif localTrue(recovery,'MIBDecoded') && localTrue(recovery,'BCHCrcPass')
    % Preserve the established combined-reception capsule. This path does
    % not authorize SI-only results and does not claim a shared-owner binding.
    for flag=["BCHCRCValid","CandidateIdentityConsistent","SSBIdentityVerified"]
        if isfield(recovery,flag)
            assert(localTrue(recovery,flag),'sixgr:mac:ra:InvalidReceivedCommonMIB', ...
                'A rejected original BCH identity cannot authorize common control.');
        end
    end
    required={'MIBDMRSTypeAPosition','CORESET0Present'};
    assert(all(isfield(recovery,required)) && ...
        isnumeric(recovery.MIBDMRSTypeAPosition) && isscalar(recovery.MIBDMRSTypeAPosition) && ...
        ismember(recovery.MIBDMRSTypeAPosition,[2 3]) && ...
        (islogical(recovery.CORESET0Present)||isnumeric(recovery.CORESET0Present)) && ...
        isreal(recovery.CORESET0Present) && isscalar(recovery.CORESET0Present) && ...
        ismember(recovery.CORESET0Present,[0 1]), ...
        'sixgr:mac:ra:InvalidReceivedCommonMIB','Preserve original combined MIB/CORESET0 fields.');
    common=struct('Source',"decoded_mib_bch_transport_block", ...
        'ReceptionRelationship',"original_combined_BCH_and_SI_result", ...
        'DMRSTypeAPosition',double(recovery.MIBDMRSTypeAPosition), ...
        'CORESET0Present',logical(recovery.CORESET0Present));
    if common.CORESET0Present
        assert(all(isfield(recovery,{'CORESET0NumRB','CORESET0RBStart'})), ...
            'sixgr:mac:ra:InvalidReceivedCommonMIB','Present CORESET0 requires its original geometry.');
        common.CORESET0NumRB=localInteger(recovery.CORESET0NumRB,1);
        common.CORESET0RBStart=localInteger(recovery.CORESET0RBStart,0);
    end
    % An explicit original absence retains resolveRARDCIReference's existing
    % decoded-initial-DL-BWP branch. Do not invent CORESET0 geometry for it.
end
end

function value=localInteger(value,minimum)
assert(isa(value,'double') && isreal(value) && isscalar(value) && ...
    isfinite(value) && value==fix(value) && value>=minimum && value<=flintmax, ...
    'sixgr:mac:ra:ReceivedCommonMIBAvailabilityMismatch','Retain exact original numeric clocks/resources.');
end

function tf=localTrue(s,name)
tf=false;
if ~isfield(s,name), return; end
v=s.(name);
tf=(islogical(v)||isnumeric(v)) && isreal(v) && isscalar(v) && isfinite(v) && v==1;
end
