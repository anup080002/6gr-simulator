function msg4=buildNRMsg4ContentionResolution(receivedCCCH,transaction)
% Original received CCCH identity + actual DL-CCCH RRCSetup.
% No configured/encoded final C-RNTI exists in this MAC CE or RRC message.
identity=sixgr.l2.mac.requireMACOctets(receivedCCCH);
assert(numel(identity)==6,'sixgr:mac:ra:InvalidNRContentionIdentity','Use the original48-bit received CCCH SDU.');
rrc=sixgr.rrc.asn1.NRAccessMessageCodec.encode("setup", ...
    struct('transaction_id',transaction,'cell_group_id',0,'srb1_lcid',1));
subs=[struct('LCID',62,'Payload',identity,'OwnerID',"UEContentionResolutionIdentity"); ...
    struct('LCID',0,'Payload',rrc.Bytes,'OwnerID',"RRCSetup/"+rrc.SHA256)];
mac=sixgr.l2.mac.MACPDUAssembler.assemble("DL",subs,7+2+numel(rrc.Bytes));
msg4=struct('PayloadBytes',mac.Bytes(:),'PayloadBits',localBits(mac.Bytes), ...
    'PayloadHex',localHex(mac.Bytes),'PayloadHash',string(sixgr.l2.mac.MACHash.of(mac.Bytes)), ...
    'ContentionIdentityBytes',identity(:),'ContentionIdentity',localHex(identity), ...
    'FinalCRNTI',NaN,'RRCSetupPresent',true, ...
    'RRCSetup',struct('MessageType',"RRCSetup",'TransactionID',transaction,'SRB1LCID',1), ...
    'RRCSetupSHA256',rrc.SHA256,'RRCCodecEvidence',rrc,'MACSubPDUs',subs, ...
    'EncodingProfile',"nr_rrc_access_base_srb1_uper_v1", ...
    'Scope',"standard_MAC_contention_CE_and_base_RRC_UPER_not_received_activation");
end
function bits=localBits(bytes)
bits=reshape(int8(bitget(repmat(bytes(:),1,8),repmat(8:-1:1,numel(bytes),1))).',[],1);
end
function value=localHex(bytes)
value=upper(string(reshape(dec2hex(bytes,2).',1,[])));
end
