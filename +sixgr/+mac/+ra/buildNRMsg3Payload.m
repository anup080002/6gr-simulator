function msg3=buildNRMsg3Payload(identityType,identityValue,establishmentCause)
% UL-CCCH 48-bit SetupRequest, not a private identity/tag payload.
rrc=sixgr.rrc.asn1.NRAccessMessageCodec.encode("setup_request", ...
    struct('identity_type',string(identityType),'identity_value',identityValue, ...
    'establishment_cause',string(establishmentCause)));
assert(numel(rrc.Bytes)==6,'sixgr:mac:ra:InvalidNRCCCHLength','Base UL-CCCH SetupRequest must contain exactly48 bits.');
sub=struct('LCID',52,'Payload',rrc.Bytes,'OwnerID',"RRCSetupRequest/"+rrc.SHA256);
mac=sixgr.l2.mac.MACPDUAssembler.assemble("UL",sub,7);
msg3=struct('PayloadBytes',mac.Bytes(:),'PayloadBits',localBits(mac.Bytes), ...
    'PayloadHex',localHex(mac.Bytes),'PayloadHash',string(sixgr.l2.mac.MACHash.of(mac.Bytes)), ...
    'ContentionIdentityBytes',rrc.Bytes(:),'ContentionIdentity',rrc.Hex, ...
    'ContentionIdentitySource',"first_48_bits_original_UL_CCCH_SDU", ...
    'RRCSetupRequestPresent',true,'RRCSetupRequest',rrc.Semantic, ...
    'RRCSetupRequestSHA256',rrc.SHA256,'RRCCodecEvidence',rrc, ...
    'MACSubPDUs',sub,'EncodingProfile',"nr_rrc_access_base_srb1_uper_v1", ...
    'Scope',"standard_MAC_UL_CCCH48_and_base_RRC_UPER_not_received_access");
end
function bits=localBits(bytes)
bits=reshape(int8(bitget(repmat(bytes(:),1,8),repmat(8:-1:1,numel(bytes),1))).',[],1);
end
function value=localHex(bytes)
value=upper(string(reshape(dec2hex(bytes,2).',1,[])));
end
