function message = buildRRCSetupComplete(varargin)
%BUILDRRCSETUPCOMPLETE Build the bounded UL-DCCH SRB1 setup-complete SDU.
p = inputParser;
p.addParameter("TransactionID", 0, @(x)isnumeric(x) && isscalar(x) && ...
    isfinite(x) && x >= 0 && x <= 3 && x == fix(x));
p.addParameter("SRB1LCID", 1, @(x)isnumeric(x) && isscalar(x) && ...
    isfinite(x) && x >= 1 && x <= 32 && x == fix(x));
p.addParameter("UEIdentity", "", @(x)ischar(x) || (isstring(x) && isscalar(x)));
p.parse(varargin{:});
identity = string(p.Results.UEIdentity);
identityBytes = uint8(unicode2native(char(identity), "UTF-8"));
if isempty(identityBytes) || numel(identityBytes) > 255
    error("sixgr:mac:ra:InvalidRRCSetupComplete", ...
        "RRCSetupComplete requires a 1..255 octet UE identity.");
end
bytes = uint8([51; uint8(p.Results.TransactionID); ...
    uint8(p.Results.SRB1LCID); uint8(numel(identityBytes)); ...
    identityBytes(:)]);
message = struct( ...
    "MessageType", "RRCSetupComplete", ...
    "TransactionID", double(p.Results.TransactionID), ...
    "SRB1LCID", double(p.Results.SRB1LCID), ...
    "UEIdentity", identity, ...
    "PayloadBytes", bytes(:), ...
    "PayloadBits", localBytesToBits(bytes), ...
    "PayloadHex", upper(string(reshape(dec2hex(bytes(:), 2).', 1, []))), ...
    "PayloadHash", sixgr.rrc.asn1.sha256Hex(bytes));
end

function bits = localBytesToBits(bytes)
bytes = uint8(bytes(:));
bits = zeros(numel(bytes) * 8, 1, "int8");
for ii = 1:numel(bytes)
    for jj = 1:8
        bits((ii - 1) * 8 + jj) = int8( ...
            bitand(bitshift(bytes(ii), -(8 - jj)), 1));
    end
end
end
