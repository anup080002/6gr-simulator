function [f,hz,probeAccounting]=validateCSIRSOriginalOperator(r,reception,p,support)
id='sixgr:truth:CSIRSLinearModelOperator'; c=p.Carrier; f=r.FFTSupport; t=r.Timing; v=r.Frequency;
for name=["NCellID","NSizeGrid","NStartGrid","NFrame","NSlot"]
    assert(numericScalarEqual(r.Carrier.(name),c.(name)),id,'Original numeric carrier changed.');
end
assert(isTextEqual(r.Carrier.CyclicPrefix,c.CyclicPrefix)&& ...
    numericScalarEqual(r.Carrier.SubcarrierSpacing_kHz,c.SubcarrierSpacing)&&isequal(f.Available,true)&& ...
    string(f.RuntimeMATLABRelease)==string(version('-release'))&& ...
    string(f.EngineUsed)=="canonical_nrOFDMDemodulate"&& ...
    string(f.SampleCoordinateDomain)=="relative_to_original_preRF_capture_start_zero_based_half_open"&& ...
    string(f.FFTWindowRule)=="symbol_start_plus_fix_CP_times_fraction"&& ...
    numericScalarEqual(f.OFDMWindowingSamples,0)&&numericScalarEqual(f.SampleRateHz,p.SampleRateHz)&& ...
    numericScalarEqual(f.Nfft,p.Tx.OFDMInfo.Nfft)&& ...
    f.SampleRateHz==f.Nfft*c.SubcarrierSpacing*1000&& ...
    isequal(t.OracleTimingUsed,false)&&isequal(t.ReceiverZeroPaddingUsed,false)&& ...
    isequaln(t.AppliedTimingCorrectionSamples,reception.PhysicalMeasurementReceiveTiming.AppliedTimingCorrectionSamples)&& ...
    isequaln(t.DemodulatedSampleCount,reception.PhysicalMeasurementReceiveTiming.DemodulatedSampleCount)&& ...
    hash(support)==string(f.ResourceSupportSHA256)&&numericScalarEqual(f.PhysicalRECount,size(support,1)), ...
    id,'Unsupported or altered original native FFT operator.');
assert(any(string(r.ContractVersion)==["sixgr.csirs.physical_demodulation/v1", ...
    "sixgr.csirs.physical_demodulation/v2"]),id,'Unknown original demodulation contract.');
probeAccounting=sixgr.phy.waveform.validateRecordedOFDMFFTAuthority(f,c,double(f.Nfft),double(f.SampleRateHz), ...
    double(f.CyclicPrefixFraction),double(c.SymbolsPerSlot),0, ...
    string(r.ContractVersion)=="sixgr.csirs.physical_demodulation/v1");
tracking=reception.PhysicalMeasurementTrackingCorrection;
assert(islogical(v.CFOCorrectionApplied)&&isscalar(v.CFOCorrectionApplied)&& ...
    string(v.PhaseOrigin)=="original_preRF_capture_start_zero_based"&& ...
    isequal(v.CFOCorrectionApplied,tracking.CFOCorrectionApplied)&& ...
    string(v.Source)==string(tracking.Source)&&string(v.Status)==string(tracking.Status),id, ...
    'Use the original pre-RF oscillator decision and full-capture phase origin.');
hz=tracking.CFOCorrectionApplied_Hz;
if v.CFOCorrectionApplied
    assert(isnumeric(hz)&&isreal(hz)&&isscalar(hz)&&isfinite(hz)&& ...
        isequaln(double(hz),v.CFOCorrectionApplied_Hz),id,'Applied CFO scalar changed.');
else
    assert(isempty(v.CFOCorrectionApplied_Hz)&&isnumeric(hz)&&isscalar(hz)&&isnan(hz),id, ...
        'Absent CFO remains absent, not an invented applied zero.');
end
native=nrOFDMInfo(c,'Nfft',double(f.Nfft),'SampleRate',double(f.SampleRateHz),'Windowing',0);
L=double(c.SymbolsPerSlot); at=mod(double(c.NSlot),double(c.SlotsPerSubframe))*L+(1:L);
cp=double(native.CyclicPrefixLengths(at)); lengths=double(native.SymbolLengths(at));
cp=cp(:).'; lengths=lengths(:).'; symbols=unique(support(:,2)).';
assert(numericVectorEqual(f.CyclicPrefixLengths,cp)&&numericVectorEqual(f.SymbolLengths,lengths)&& ...
    all(lengths==cp+f.Nfft)&&sum(lengths)==t.DemodulatedSampleCount&& ...
    numericVectorEqual(f.SelectedSymbols0,symbols)&& ...
    isnumeric(f.CyclicPrefixFraction)&&isreal(f.CyclicPrefixFraction)&&isscalar(f.CyclicPrefixFraction)&& ...
    isfinite(f.CyclicPrefixFraction)&&f.CyclicPrefixFraction>=0&&f.CyclicPrefixFraction<=1,id,'Native CP geometry changed.');
starts=[0 cumsum(lengths(1:end-1))];
first=t.AppliedTimingCorrectionSamples+starts(symbols+1)+fix(cp(symbols+1)*f.CyclicPrefixFraction);
windows=[first(:) first(:)+f.Nfft];
assert(isnumeric(f.FFTIntervals)&&isreal(f.FFTIntervals)&&all(isfinite(f.FFTIntervals),'all'),id, ...
    'Original FFT intervals must remain numeric.');
actual=double(f.FFTIntervals);
if isvector(actual)&&numel(actual)==2, actual=reshape(actual,1,2); end
assert(isequal(actual,windows)&&all(windows(:,1)>=0)&& ...
    all(windows(:,2)<=p.ReceiveEndSampleExclusive-p.ReceiveStartSample),id,'Exact selected FFT support changed.');
end

function tf=numericScalarEqual(a,b)
tf=isnumeric(a)&&isreal(a)&&isscalar(a)&&~issparse(a)&&isfinite(a)&& ...
    isnumeric(b)&&isreal(b)&&isscalar(b)&&isfinite(b)&&isequal(double(a),double(b));
end
function tf=numericVectorEqual(a,b)
tf=isnumeric(a)&&isreal(a)&&isvector(a)&&~issparse(a)&&all(isfinite(a),'all')&& ...
    isequal(double(a(:)),double(b(:)));
end
function value=hash(x), value=sixgr.phy.waveform.WaveformHash.runtimeArray(x); end
function tf=isTextEqual(a,b)
tf=((ischar(a)&&isrow(a))||(isstring(a)&&isscalar(a)&&~ismissing(a)))&&string(a)==string(b);
end
