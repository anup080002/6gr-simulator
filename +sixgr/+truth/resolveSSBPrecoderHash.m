function hash = resolveSSBPrecoderHash(evidence, observedIndex)
%RESOLVESSBPRECODERHASH Match executed sparse resource IDs, not index+1.
hash = "";
hashes = string(sixgr.util.structGet(evidence, 'PrecoderMatrixSHA256', strings(0,1)));
if isempty(hashes) || ~isfinite(observedIndex), return; end
indices = double(sixgr.util.structGet(evidence, 'ActiveSSBIndices0Based', []));
assert(numel(indices) == numel(hashes) && all(isfinite(indices)) && ...
    all(indices >= 0 & indices == fix(indices)) && numel(unique(indices)) == numel(indices), ...
    'sixgr:truth:InvalidSSBPrecoderIdentity', ...
    'Executed SSB indices and precoder hashes must have one-to-one ownership.');
hit = indices == observedIndex;
assert(nnz(hit) == 1, 'sixgr:truth:InvalidSSBPrecoderIdentity', ...
    'The observed SSB has no unique executed precoder.');
hash = hashes(hit);
assert(isscalar(hash) && ~ismissing(hash) && ...
    ~isempty(regexp(char(hash), '^[0-9a-fA-F]{64}$', 'once')), ...
    'sixgr:truth:InvalidSSBPrecoderIdentity', 'Executed precoder SHA256 is invalid.');
end
