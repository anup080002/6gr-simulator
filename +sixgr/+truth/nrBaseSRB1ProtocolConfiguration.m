function config=nrBaseSRB1ProtocolConfiguration(descriptor,direction)
% Supported decoded defaultSRB1, not admission.
% TS38.331 V18.8.0 9.2.1. No dedicated DRB/security is installed here.
assert(descriptor.ContractVersion=="NR_cell_connection_descriptor/v1" && ...
    any(string(direction)==["UL","DL"]),'sixgr:truth:IssuedNRSRB1','Original connection/direction required.');
identity=descriptor.ConnectionID;epoch=descriptor.ConfigurationEpoch;fs=descriptor.SampleRateHz;
base=struct('UEID',identity,'BearerID',identity+"/SRB1",'QFI',0,'BearerType',"SRB", ...
    'SRBID',1,'LCID',1,'PDCPSNBits',12,'RLCSNBits',12,'Direction',string(direction), ...
    'ConfigurationEpoch',epoch,'CipherAlgorithm',"NEA0",'IntegrityAlgorithm',"NIA0", ...
    'SecurityActive',false,'ReorderingTime_s',Inf,'PollPDU',Inf,'PollByte',Inf, ...
    'MaxRetxThreshold',8,'RLCARQEnabled',true,'SampleRateHz',fs,'ClockEpoch',descriptor.ClockEpoch, ...
    'RLCPollRetransmit_s',0.045,'RLCReassembly_s',0.035,'RLCStatusProhibit_s',0);
scope=struct('ExecutionRunID',descriptor.ExecutionRunID,'UEID',identity, ...
    'ServingCell',descriptor.ServingCell,'RNTI',descriptor.RNTI,'SRBID',1,'LCID',1, ...
    'Direction',string(direction),'ConfigurationEpoch',epoch,'ClockEpoch',descriptor.ClockEpoch, ...
    'SampleRateHz',fs,'ProtocolConfigurationSHA256',sixgr.l2.mac.MACHash.of(orderfields(base)));
config=base;config.EndpointAdmissionMode="original_setup_required";config.EndpointAdmissionScope=scope;
config.OriginalConnectionScope=scope;config.OriginalConnectionScope.BearerID=base.BearerID;
end
