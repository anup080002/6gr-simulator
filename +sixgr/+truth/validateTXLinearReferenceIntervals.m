function complete=validateTXLinearReferenceIntervals(T,library,intervals,chainPower)
% Validate compact original-owner joins and model arithmetic, not new PHY.
id='sixgr:truth:TXLinearReferenceClosure'; complete=false;
if nargin<4, chainPower=sixgr.truth.rfChainPowerInterval(); end
assert(isstruct(library),id,'Require the immutable owner registration library.');
ids=strings(numel(library),1); endpoints=ids;
for k=1:numel(library)
    sixgr.rf.InstalledTXLinearReference.validateRegistration(library(k));
    ids(k)=string(library(k).RegistrationSHA256); endpoints(k)=string(library(k).EndpointID);
end
assert(numel(unique(ids))==numel(ids)&&numel(unique(endpoints))==numel(endpoints),id, ...
    'One immutable aggregate-model registration per enabled transmitter.');
prototype=sixgr.truth.txLinearReferenceInterval();
assert(istable(T)&&all(ismember(prototype.Properties.VariableNames,T.Properties.VariableNames)),id, ...
    'Missing separate TX model interval columns.');
assert(numel(unique(string(T.EndpointID)+"|"+string(T.StartSample)))==height(T),id,'Duplicate TX model interval.');
staticHashes=strings(numel(library),1);
for k=1:height(T)
    row=T(k,:); at=find(ids==string(row.RegistrationSHA256));
    assert(isscalar(at),id,'Unknown original owner registration.'); reg=library(at);
    base=intervals(intervals.Role=="TX"&intervals.EndpointID==row.EndpointID&intervals.StartSample==row.StartSample,:);
    assert(height(base)==1,id,'Model interval lacks its original RF execution.');
    assert(istable(chainPower)&&all(ismember({'Role','EndpointID','StartSample','EndSampleExclusive', ...
        'WaveformAmplitudeUnit'},chainPower.Properties.VariableNames)),id,'Original chain power/unit evidence required.');
    unit=chainPower(chainPower.Role=="TX"&chainPower.EndpointID==row.EndpointID&chainPower.StartSample==row.StartSample,:);
    assert(height(unit)==1&&unit.EndSampleExclusive==base.EndSampleExclusive&& ...
        string(unit.WaveformAmplitudeUnit)==string(reg.WaveformAmplitudeUnit),id, ...
        'Model units must match the original RF chain-power evidence, not merely a model declaration.');
    r=jsondecode(char(row.ReceiptJSON));
    exact(r,{'ContractVersion','Source','RegistrationSHA256','OriginalInputChunkSHA256', ...
        'OriginalOutputChunkSHA256','OriginalOwnerBindingVerified','ReceiverEstimatorInput', ...
        'AdditionalRFExecutions','AdditionalChannelExecutions','Adapter'},id);
    assert(string(r.ContractVersion)=="sixgr.rf.original_owner_TX_linear_reference/v1"&& ...
        string(r.Source)=="original_registered_TX_RF_owner_fixed_linear_diagnostic_model"&& ...
        string(r.RegistrationSHA256)==ids(at),id,'Incorrect original-owner model scope.');
    flag(r.OriginalOwnerBindingVerified,true,id); flag(r.ReceiverEstimatorInput,false,id);
    assert(isequal(r.AdditionalRFExecutions,0)&&isequal(r.AdditionalChannelExecutions,0),id,'No additional RF/channel execution allowed.');
    a=r.Adapter;
    exact(a,{'ContractVersion','Source','ReferenceID','Role','EndpointID','Direction','ConfigurationEpoch', ...
        'OriginSample','ModelHistoryStartSample','ComponentBirth','StartSample','EndSampleExclusive', ...
        'SampleRateHz','NumAntennas','NumericClass','WaveformAmplitudeUnit','InstallationSHA256', ...
        'StaticOperatorSHA256','OriginalRFInputSHA256','OriginalRFOutputSHA256','OriginalRFHashSerialization', ...
        'ModelInputSHA256','ReferenceOutputSHA256','ModelHashSerialization','IntervalOperatorSHA256', ...
        'ModelPAStateSHA256','ModelDelayStateSHA256','HistoryAuthority','DACReferenceModel','PAReferenceModel', ...
        'AggregateCommonIQDCIncluded','SuppliedOperandsValidated','OriginalOwnerVerified', ...
        'SharedRuntimeIntegrationQualified','ActualNonlinearPortAttribution','StandardizedPowerAccuracyQualified', ...
        'HardwareQualified','ReceiverEstimatorInput','AdditionalRFExecutions','AdditionalChannelExecutions', ...
        'ResidualAvailable','ResidualSHA256','ReferenceEnergy','ActualAggregateOutputEnergy','ResidualEnergy', ...
        'ReferenceResidualCrossEnergy','PowerClosureRelativeError'},id);
    for name=["ContractVersion","Source","ReferenceID","Role","EndpointID","Direction", ...
            "NumericClass","WaveformAmplitudeUnit","HistoryAuthority","DACReferenceModel","PAReferenceModel", ...
            "OriginalRFHashSerialization","ModelHashSerialization"]
        v=a.(name); assert((ischar(v)||isstring(v))&&isscalar(string(v))&& ...
            ~ismissing(string(v))&&strlength(strtrim(string(v)))>0,id,'Scalar explicit model provenance required.');
    end
    for name=["ConfigurationEpoch","OriginSample","ModelHistoryStartSample","StartSample","EndSampleExclusive","NumAntennas"]
        v=a.(name); assert(isa(v,'double')&&isreal(v)&&isscalar(v)&&isfinite(v)&& ...
            v>=0&&v<flintmax&&v==fix(v),id,'Exact scalar model clock/population required.');
    end
    assert(string(a.ContractVersion)=="sixgr.rf.AppliedTXLinearReferenceStream/v1"&& ...
        string(a.Source)=="validated_supplied_original_operator_operands"&&string(a.Role)=="aggregate"&& ...
        isscalar(string(a.ReferenceID))&&strlength(string(a.ReferenceID))>0&& ...
        string(a.EndpointID)==string(reg.EndpointID)&&string(a.EndpointID)==base.EndpointID&& ...
        string(a.Direction)==string(reg.Direction)&&string(a.Direction)==base.Direction&& ...
        a.ConfigurationEpoch==reg.ConfigurationEpoch&&a.ConfigurationEpoch==base.ConfigurationEpoch&& ...
        a.SampleRateHz==reg.SampleRateHz&&a.SampleRateHz==base.SampleRateHz&& ...
        a.NumAntennas==reg.NumAntennas&&a.NumAntennas==base.PhysicalPortCount&& ...
        a.OriginSample==reg.OriginSample&&a.ModelHistoryStartSample==reg.OriginSample&& ...
        a.StartSample==base.StartSample&&a.EndSampleExclusive==base.EndSampleExclusive&& ...
        a.StartSample>=a.OriginSample&& ...
        string(a.WaveformAmplitudeUnit)==string(reg.WaveformAmplitudeUnit)&& ...
        any(string(a.NumericClass)==["single","double"])&& ...
        string(a.InstallationSHA256)==ids(at)&& ...
        string(a.OriginalRFInputSHA256)==base.InputWaveformSHA256&& ...
        string(a.OriginalRFOutputSHA256)==base.OutputWaveformSHA256,id,'Original RF identity/clock/units changed.');
    assert(isstruct(a.ComponentBirth)&&isscalar(a.ComponentBirth)&&isempty(fieldnames(a.ComponentBirth)),id, ...
        'Aggregate model history starts at the installed original origin.');
    assert(string(a.HistoryAuthority)=="independent_declared_zero_model_state_not_original_aggregate_memory"&& ...
        string(a.DACReferenceModel)=="identity_converter_reference_residual_retained"&& ...
        string(a.PAReferenceModel)=="fixed_declared_first_order_PA"&& ...
        string(a.OriginalRFHashSerialization)=="sixgr.rf.waveformSHA256"&& ...
        string(a.ModelHashSerialization)=="WaveformHash.runtimeArray",id,'Declared model policy or hash representation changed.');
    for name=["OriginalOwnerVerified","SharedRuntimeIntegrationQualified","ActualNonlinearPortAttribution", ...
            "StandardizedPowerAccuracyQualified","HardwareQualified","ReceiverEstimatorInput"]
        flag(a.(name),false,id);
    end
    for name=["SuppliedOperandsValidated","ResidualAvailable"], flag(a.(name),true,id); end
    assert(islogical(a.AggregateCommonIQDCIncluded)&&isscalar(a.AggregateCommonIQDCIncluded)&& ...
        isequal(a.AdditionalRFExecutions,0)&&isequal(a.AdditionalChannelExecutions,0),id,'Invalid model execution scope.');
    for name=["StaticOperatorSHA256","OriginalRFInputSHA256","OriginalRFOutputSHA256","ModelInputSHA256", ...
            "ReferenceOutputSHA256","IntervalOperatorSHA256","ModelPAStateSHA256","ModelDelayStateSHA256","ResidualSHA256"]
        hash(a.(name),id);
    end
    hash(r.OriginalInputChunkSHA256,id); hash(r.OriginalOutputChunkSHA256,id);
    if staticHashes(at)=="", staticHashes(at)=string(a.StaticOperatorSHA256); end
    assert(staticHashes(at)==string(a.StaticOperatorSHA256),id,'Static RF operators changed within an installed model.');
    for name=["ReferenceEnergy","ActualAggregateOutputEnergy","ResidualEnergy","ReferenceResidualCrossEnergy","PowerClosureRelativeError"]
        v=a.(name); assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&isfinite(v),id,'Finite scalar model energy required.');
        if name~="ReferenceResidualCrossEnergy", assert(v>=0,id,'Negative squared energy/closure error.'); end
    end
    scale=max(1,a.ActualAggregateOutputEnergy);
    closure=a.ReferenceEnergy+a.ResidualEnergy+a.ReferenceResidualCrossEnergy;
    relative=abs(a.ActualAggregateOutputEnergy-closure)/max(a.ActualAggregateOutputEnergy,realmin);
    assert(abs(a.ActualAggregateOutputEnergy-base.OutputSquaredMagnitudeSum)<=1e-12*scale&& ...
        abs(a.ActualAggregateOutputEnergy-closure)<=1e-12*scale&&a.PowerClosureRelativeError<=1e-10&& ...
        abs(a.PowerClosureRelativeError-relative)<=64*eps(max(1,relative)),id, ...
        'Keep signed cross energy and actual aggregate energy; never replace actual RF power by the reference.');
    expected=sixgr.truth.txLinearReferenceInterval(r,base);
    assert(string(jsonencode(r))==row.ReceiptJSON,id,'Receipt JSON must retain its original compact typed content.');
    for name=string(prototype.Properties.VariableNames)
        assert(isequaln(expected.(name),row.(name)),id,'TX model field %s or receipt hash changed.',name);
    end
end
expected=intervals(intervals.Role=="TX"&ismember(intervals.EndpointID,endpoints),:);
assert(height(T)==height(expected),id,'Every enabled TX requires every committed interval, including zero input.');
complete=~isempty(library)&&~isempty(expected);
end
function exact(s,names,id)
assert(isstruct(s)&&isscalar(s)&&isequal(sort(string(fieldnames(s))),sort(string(names(:)))),id, ...
    'Only compact declared receipt fields are allowed; no sample/operator arrays.');
end
function flag(v,value,id)
assert(islogical(v)&&isscalar(v)&&v==value,id,'False qualification flags must not be promoted.');
end
function hash(v,id)
assert((isstring(v)||ischar(v))&&isscalar(string(v))&& ...
    ~isempty(regexp(char(v),'^[0-9a-f]{64}$','once')),id,'Original complete lowercase SHA256 required.');
end
