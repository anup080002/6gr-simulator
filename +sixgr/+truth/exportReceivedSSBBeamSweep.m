function trials=exportReceivedSSBBeamSweep(runFolder,trials)
%EXPORTRECEIVEDSSBBEAMSWEEP Publish exact connected PBCH candidate evidence.
% No new waveform, beam selection, metric estimation or success filtering.
% Retain the source table unchanged, including failed/unselected candidates,
% native slot coordinates, power units, source identity and receiver clocks.
arguments
    runFolder (1,1) string
    trials table
end
if isempty(trials), return; end
required=["SSBIndex","SelectedBeamFlag","SelectedSSBIndex", ...
    "RunID","ExecutionID","ConfigHash","EvidenceScope", ...
    "SameScenarioInPathEligible"];
assert(all(ismember(required,string(trials.Properties.VariableNames))), ...
    'sixgr:truth:MissingReceivedSSBBeamEvidence', ...
    'Connected beam-sweep publication requires identity-bound receiver candidates.');
assert(all(string(trials.EvidenceScope)=="in_path") && ...
    all(trials.SameScenarioInPathEligible==true), ...
    'sixgr:truth:NonRuntimeSSBBeamEvidence', ...
    'Standalone/proxy beam sweeps cannot replace connected receiver evidence.');
for field=["RunID","ExecutionID","ConfigHash"]
    values=unique(strtrim(string(trials.(field))));
    assert(numel(values)==1 && ~ismissing(values) && strlength(values)>0, ...
        'sixgr:truth:MixedSSBBeamEvidenceIdentity', ...
        'A connected beam artifact must retain one nonempty %s.',field);
end
for field=["ProxyUsed","FallbackFlag","PlaceholderFlag"]
    if ismember(field,string(trials.Properties.VariableNames))
        assert(all(trials.(field)==false), ...
            'sixgr:truth:NonRuntimeSSBBeamEvidence', ...
            'Do not publish proxy/fallback/placeholder beam candidates.');
    end
end
layout=sixgr.report.resultLayout(runFolder);
paths=[fullfile(layout.AirInterfaceCSVDir,'ssb_pbch_sib1_beam_sweep.csv'), ...
    fullfile(layout.ControlCSVDir,'ssb_pbch_sib1_beam_sweep.csv'), ...
    fullfile(layout.BeamformingCSVDir,'ssb_pbch_sib1_beam_sweep.csv'), ...
    fullfile(layout.BeamformingCSVDir,'ssb_beam_sweep.csv')];
for path=paths
    sixgr.util.csvWriteTable(path,trials,'PreserveSchema',true);
end
end
