function evidence=captureTransmitOccupancy(samples,startSample,sampleRateHz,identity)
% Compact exact nonzero support of the contribution actually enqueued.
% Pre-node-RF physical-chain samples, including OFDM window/tail samples.
% This is NOT an RF-on measurement, mapped-symbol rectangle, RE collision,
% or proof of emission. The physical owner must subsequently commit/finish.
validateattributes(samples,{'single','double'},{'2d','nonempty','finite'});
validateattributes(startSample,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(sampleRateHz,{'numeric'},{'scalar','real','finite','positive'});
required={'Channel','TransmissionID','ObservationID','UEIndex','RNTI', ...
    'ServingCell','TransmitterID','ClockDomain','ClockEpoch'};
assert(isstruct(identity) && isscalar(identity) && all(isfield(identity,required)), ...
    'sixgr:truth:TransmitOccupancyIdentity','Bind actual contribution identity and physical clock.');
assert(any(string(identity.Channel)==["PUSCH","PUCCH"]) && ...
    string(identity.TransmitterID)=="ue_"+string(identity.UEIndex) && ...
    string(identity.ClockDomain)=="shared_physical_sample_clock/v1", ...
    'sixgr:truth:TransmitOccupancyIdentity','Only explicitly owned shared UL contributions are supported.');
for name=["UEIndex","RNTI","ServingCell"]
    validateattributes(identity.(name),{'numeric'},{'scalar','real','finite','integer','positive'});
end
validateattributes(identity.ClockEpoch,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
for name=["TransmissionID","ObservationID"]
    assert(isscalar(string(identity.(name))) && strlength(strtrim(string(identity.(name))))>0, ...
        'sixgr:truth:TransmitOccupancyIdentity','Retain nonempty actual transmission and observation IDs.');
end
active=any(samples~=0,2); % Exact zeros only; no configurable RF threshold.
edges=diff([false;active;false]);
runs=[find(edges==1)-1 find(edges==-1)-1]+double(startSample);
evidence=struct('Version',"transmit_occupancy/v1", ...
    'Source',"enqueued_physical_chain_nonzero_contribution_pre_node_RF", ...
    'Identity',identity,'StartSample',double(startSample), ...
    'EndSampleExclusive',double(startSample)+size(samples,1), ...
    'SampleRateHz',double(sampleRateHz),'NumPhysicalChains',size(samples,2), ...
    'InputSampleCount',size(samples,1),'ActiveSampleCount',nnz(active), ...
    'ActiveIntervals',runs,'HasNonzeroSamples',any(active), ...
    'InputWaveformSHA256',string(sixgr.rf.waveformSHA256(samples)), ...
    'EmissionStatus',"prepared_not_emitted");
end
