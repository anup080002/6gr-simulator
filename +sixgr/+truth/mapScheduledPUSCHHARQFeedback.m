function rows=mapScheduledPUSCHHARQFeedback(mapping,observed)
% Validate the entire receiver vector, then associate only real DL attempts.
% Protocol padding never manufactures a grant, TBS, HARQ attempt or primary row.
required={'BaseMapping','BaseMappingDigest','Digest','BitCount','PhysicalAssignmentCount', ...
    'ProtocolPaddingBitIndices','ULTotalDAIRaw','UEIndex','RNTI','TargetSlot','ConfigurationEpoch','Source'};
assert(isstruct(mapping) && isscalar(mapping) && all(isfield(mapping,required)) && ...
    mapping.Digest==sixgr.phy.pucch.PUCCHUtil.hash(rmfield(mapping,{'BaseMapping','Digest'})) && ...
    mapping.Source=="gnb_actual_dl_mapping_and_scheduled_ul_total_dai", ...
    'sixgr:truth:ChangedScheduledPUSCHHARQMapping','Retain the exact independently bound PUSCH mapping.');
base=mapping.BaseMapping;
n=base.BitCount;
raw=mapping.ULTotalDAIRaw;
assert(isnumeric(raw) && isscalar(raw) && isreal(raw) && isfinite(raw) && ...
    raw==fix(raw) && raw>=0 && raw<=3, ...
    'sixgr:truth:ChangedScheduledPUSCHHARQMapping','Retain an exact two-bit scheduled UL DAI.');
width=4*floor((n-1)/4)+raw+1+4*double(raw+1<mod(n-1,4)+1);
assert(mapping.BaseMappingDigest==base.Digest && mapping.BitCount==width && ...
    mapping.PhysicalAssignmentCount==n && ...
    isequal(mapping.ProtocolPaddingBitIndices,(n+1:width).') && ...
    mapping.UEIndex==base.UEIndex && mapping.RNTI==base.RNTI && ...
    mapping.TargetSlot==base.TargetSlot && mapping.ConfigurationEpoch==base.ConfigurationEpoch, ...
    'sixgr:truth:ChangedScheduledPUSCHHARQMapping','Receive width and physical assignment identities disagree.');
fields={'MappingDigest','UEIndex','RNTI','TargetSlot','DecodedBits','DecodeOk','DTXFlag','Transport'};
assert(isstruct(observed) && isscalar(observed) && all(isfield(observed,fields)) && ...
    string(observed.MappingDigest)==mapping.Digest && string(observed.Transport)=="PUSCH", ...
    'sixgr:truth:ScheduledPUSCHHARQObservationMismatch','Bind the actual PUSCH observation to this receive hypothesis.');
bits=observed.DecodedBits;
assert((isnumeric(bits)||islogical(bits)) && isreal(bits) && ...
    (isvector(bits)||isempty(bits)) && all(isfinite(bits(:))) && all(bits(:)==0|bits(:)==1), ...
    'sixgr:truth:InvalidReceivedHARQBit','Validate all receiver bits, including unmapped protocol padding.');
for name=["DecodeOk","DTXFlag"]
    value=observed.(name);
    assert((isnumeric(value)||islogical(value)) && isreal(value) && isscalar(value) && ...
        isfinite(value) && any(value==[0 1]), ...
        'sixgr:truth:InvalidScheduledFeedbackFlag','Receive validity flags must be scalar binary values.');
end
lengthOK=numel(bits)==width;
projected=observed;
projected.MappingDigest=base.Digest;
if lengthOK
    projected.DecodedBits=bits(1:n);
else
    projected.DecodedBits=int8([]);
end
rows=sixgr.truth.mapScheduledHARQFeedback(base,projected);
for k=1:numel(rows)
    rows(k).MappingDigest=mapping.Digest;
    rows(k).ReceiverVectorLengthMatches=lengthOK;
    rows(k).ReceiverExpectedHARQBitCount=width;
    rows(k).PhysicalAssignmentCount=n;
    rows(k).ProtocolPaddingBitCount=width-n;
end
end
