function artifacts = exportRuntimeTxIQCapture(runFolder, capture, cfg, direction)
%EXPORTRUNTIMETXIQCAPTURE Persist exact committed pre-channel transmit IQ.
%
% The canonical CSV and MAT retain the complex samples after the runtime
% power context and enabled transmitter RF impairments, immediately before
% the channel.  Per-port headerless two-column CSV files contain normalized
% I,Q values for import through Keysight PathWave Signal Generation/AWU.
% The package also includes little-endian interleaved signed-int16 WIQ and
% 89600-VSA-compatible MAT files.  The common normalization/quantization
% scale is published in the manifest; samples are never regenerated from
% grants, configured values, or plot data.

arguments
    runFolder {mustBeTextScalar}
    capture (1,1) struct
    cfg (1,1) struct
    direction {mustBeTextScalar}
end

direction = upper(strtrim(string(direction)));
if ~ismember(direction, ["DL","UL"])
    error("sixgr:truth:InvalidTxIQDirection", ...
        "Runtime Tx-IQ direction must be DL or UL.");
end
waveform = sixgr.util.structGet(capture, "Waveform", []);
sampleRateHz = double(sixgr.util.structGet(capture, "SampleRateHz", NaN));
if ~(isnumeric(waveform) && ismatrix(waveform) && ~isempty(waveform) && ...
        all(isfinite(real(waveform(:)))) && all(isfinite(imag(waveform(:)))))
    error("sixgr:truth:InvalidRuntimeTxIQWaveform", ...
        "Committed %s Tx-IQ capture is empty or non-finite.", direction);
end
if ~(isscalar(sampleRateHz) && isfinite(sampleRateHz) && sampleRateHz > 0)
    error("sixgr:truth:InvalidRuntimeTxIQSampleRate", ...
        "Committed %s Tx-IQ capture has no finite positive sample rate.", direction);
end

runFolder = char(string(runFolder));
csvDir = fullfile(runFolder, "waveform", "csv");
matDir = fullfile(runFolder, "waveform", "mat");
sixgr.util.ensureFolder(csvDir);
sixgr.util.ensureFolder(matDir);
token = lower(direction);

nSamples = size(waveform,1);
nPorts = size(waveform,2);
if nSamples < 1024
    error("sixgr:truth:KeysightTxIQMinimumLength", ...
        "Keysight M9383B/M9384B playback requires at least 1024 samples; %s capture has %d.", ...
        direction, nSamples);
end
if mod(nSamples,16) ~= 0
    error("sixgr:truth:KeysightM9384BWaveformQuantum", ...
        "Keysight M9384B playback requires a sample count divisible by 16; %s capture has %d.", ...
        direction, nSamples);
end
sampleIndex = (0:nSamples-1).';
time_s = sampleIndex ./ sampleRateHz;
canonicalT = table(sampleIndex, time_s, ...
    'VariableNames', {'SampleIndex','Time_s'});
for portIndex = 1:nPorts
    canonicalT.(sprintf('I_Port%d', portIndex)) = double(real(waveform(:,portIndex)));
    canonicalT.(sprintf('Q_Port%d', portIndex)) = double(imag(waveform(:,portIndex)));
end
canonicalPath = fullfile(csvDir, "final_tx_iq_" + token + ".csv");
sixgr.util.csvWriteTable(canonicalPath, canonicalT);

fullScale = max(abs([real(waveform(:)); imag(waveform(:))]));
if ~(isfinite(fullScale) && fullScale > 0)
    error("sixgr:truth:ZeroRuntimeTxIQWaveform", ...
        "Committed %s Tx-IQ capture has zero full-scale amplitude.", direction);
end
normalized = double(waveform) ./ double(fullScale);
keysightPaths = strings(nPorts,1);
keysightHashes = strings(nPorts,1);
keysightRelativePaths = strings(nPorts,1);
keysightWIQPaths = strings(nPorts,1);
keysightWIQHashes = strings(nPorts,1);
keysightWIQRelativePaths = strings(nPorts,1);
keysightVSAMATPaths = strings(nPorts,1);
keysightVSAMATHashes = strings(nPorts,1);
keysightVSAMATRelativePaths = strings(nPorts,1);
quantizedPeakCodes = zeros(nPorts,1);
quantizationErrors = zeros(nPorts,1);
quantizationClippedCounts = zeros(nPorts,1);
centerFrequencyHz = double(sixgr.util.structGet(cfg, ...
    "channel.fc_Hz", sixgr.util.structGet(cfg, "phy.fc_Hz", NaN)));
for portIndex = 1:nPorts
    keysightPaths(portIndex) = string(fullfile(csvDir, sprintf( ...
        'final_tx_iq_%s_port%d_keysight.csv', token, portIndex)));
    % Keysight user-defined CSV convention: one numeric I,Q sample per
    % line, no column-name row. Sample rate and common scaling are bound by
    % the adjacent manifest rather than embedded as fake waveform samples.
    writematrix([real(normalized(:,portIndex)), imag(normalized(:,portIndex))], ...
        keysightPaths(portIndex), "Delimiter", ",");
    keysightHashes(portIndex) = localFileSHA256(keysightPaths(portIndex));
    keysightRelativePaths(portIndex) = localRelativePath( ...
        runFolder, keysightPaths(portIndex));

    % M9383B/M9384B Keysight 16-bit binary: signed int16 samples in the
    % exact I0,Q0,I1,Q1,... order.  Use an explicit little-endian package;
    % the byte order and scale are manifest fields, never an implicit host
    % convention.  Symmetric +/-32767 mapping avoids an asymmetric -32768
    % endpoint while preserving the normalized waveform within one LSB.
    portWaveform = normalized(:,portIndex);
    scaledI = round(real(portWaveform) .* 32767);
    scaledQ = round(imag(portWaveform) .* 32767);
    quantizationClippedCounts(portIndex) = sum( ...
        scaledI < -32767 | scaledI > 32767 | ...
        scaledQ < -32767 | scaledQ > 32767);
    quantizedI = int16(max(-32767,min(32767,scaledI)));
    quantizedQ = int16(max(-32767,min(32767,scaledQ)));
    interleaved = zeros(2*nSamples,1,"int16");
    interleaved(1:2:end) = quantizedI;
    interleaved(2:2:end) = quantizedQ;
    keysightWIQPaths(portIndex) = string(fullfile(csvDir, sprintf( ...
        'final_tx_iq_%s_port%d_keysight_le16.wiq', token, portIndex)));
    localAtomicInt16Write(keysightWIQPaths(portIndex), interleaved, "ieee-le");
    keysightWIQHashes(portIndex) = localFileSHA256(keysightWIQPaths(portIndex));
    keysightWIQRelativePaths(portIndex) = localRelativePath( ...
        runFolder, keysightWIQPaths(portIndex));
    quantizedPeakCodes(portIndex) = max(abs(double(interleaved)));
    reconstructed = complex(double(quantizedI),double(quantizedQ)) ./ 32767;
    quantizationErrors(portIndex) = max(abs(reconstructed-portWaveform));

    % 89600 VSA MATLAB source-playback contract.  Parameter names and data
    % types are case sensitive: Y is complex single and XDelta is the sample
    % period.  One file per physical port permits RecallMultifile without
    % inventing an unsupported multi-channel layout.
    vsaPayload = struct( ...
        "Y", single(portWaveform), ...
        "XDelta", double(1/sampleRateHz), ...
        "InputCenter", centerFrequencyHz, ...
        "InputZoom", 1, ...
        "XDomain", 2);
    keysightVSAMATPaths(portIndex) = string(fullfile(matDir, sprintf( ...
        'final_tx_iq_%s_port%d_89600vsa.mat', token, portIndex)));
    sixgr.util.matSave(keysightVSAMATPaths(portIndex), vsaPayload, ...
        "UseArtifactStore", false);
    keysightVSAMATHashes(portIndex) = localFileSHA256(keysightVSAMATPaths(portIndex));
    keysightVSAMATRelativePaths(portIndex) = localRelativePath( ...
        runFolder, keysightVSAMATPaths(portIndex));
end

metadata = struct( ...
    "Direction", direction, ...
    "EndpointType", string(sixgr.util.structGet(capture, "EndpointType", "unspecified_legacy_capture")), ...
    "ArtifactScope", string(sixgr.util.structGet(capture, "ArtifactScope", "unspecified_legacy_capture")), ...
    "UEIndex", double(sixgr.util.structGet(capture, "UEIndex", NaN)), ...
    "ServingCell", double(sixgr.util.structGet(capture, "ServingCell", NaN)), ...
    "GrantContextId", string(sixgr.util.structGet(capture, "GrantContextId", "")), ...
    "CompositeTransmitterWaveform", logical(sixgr.util.structGet(capture, "CompositeTransmitterWaveform", false)), ...
    "VSGImportScope", string(sixgr.util.structGet(capture, "VSGImportScope", "scope_not_declared")), ...
    "SampleRateHz", sampleRateHz, ...
    "CenterFrequencyHz", centerFrequencyHz, ...
    "SampleCount", double(nSamples), ...
    "PortCount", double(nPorts), ...
    "Frame", double(sixgr.util.structGet(capture, "Frame", NaN)), ...
    "Slot", double(sixgr.util.structGet(capture, "Slot", NaN)), ...
    "CapturePoint", string(sixgr.util.structGet(capture, "CapturePoint", "")), ...
    "WaveformAuthority", string(sixgr.util.structGet(capture, "WaveformAuthority", "")), ...
    "CommonNormalizationFullScale", double(fullScale), ...
    "NormalizedPeak", double(max(abs([real(normalized(:)); imag(normalized(:))]))), ...
    "NormalizedRMS", double(sqrt(mean(abs(normalized(:)).^2))), ...
    "PlaybackRepeatPolicy", string(sixgr.util.structGet(capture, ...
        "PlaybackRepeatPolicy", "operator_selected_no_implicit_repeat")), ...
    "WaveformSHA256", localComplexSHA256(waveform));
matPath = fullfile(matDir, "final_tx_iq_" + token + ".mat");
% Publish through the repository's atomic MAT writer.  Direct HDF5-backed
% save() calls can leave a partially-created target behind when MATLAB is
% interrupted or when OneDrive briefly opens the destination.  A later
% truth run must replace that stale file atomically; it must never append
% to, or attempt to repair, a corrupt capture in place.
sixgr.util.matSave(matPath, struct( ...
    "waveform", waveform, "metadata", metadata), ...
    "UseArtifactStore", false);

manifestPath = fullfile(csvDir, "final_tx_iq_capture_manifest.csv");
row = table(direction, metadata.EndpointType, metadata.ArtifactScope, ...
    metadata.UEIndex, metadata.ServingCell, metadata.GrantContextId, ...
    metadata.CompositeTransmitterWaveform, metadata.VSGImportScope, ...
    metadata.Frame, metadata.Slot, metadata.SampleRateHz, ...
    metadata.CenterFrequencyHz, metadata.SampleCount, metadata.PortCount, ...
    metadata.CapturePoint, metadata.WaveformAuthority, ...
    metadata.CommonNormalizationFullScale, metadata.NormalizedPeak, ...
    metadata.NormalizedRMS, metadata.WaveformSHA256, ...
    localRelativePath(runFolder, canonicalPath), localFileSHA256(canonicalPath), ...
    strjoin(keysightRelativePaths, "|"), ...
    strjoin(keysightHashes, "|"), ...
    strjoin(keysightWIQRelativePaths, "|"), ...
    strjoin(keysightWIQHashes, "|"), "little_endian", 32767, ...
    max(quantizedPeakCodes), sum(quantizationClippedCounts), ...
    max(quantizationErrors), ...
    strjoin(keysightVSAMATRelativePaths, "|"), ...
    strjoin(keysightVSAMATHashes, "|"), ...
    "Y=complex_single;XDelta=seconds;InputCenter=Hz;InputZoom=1;XDomain=2", ...
    metadata.PlaybackRepeatPolicy, true, true, ...
    "M9384B|M9383B|89600_VSA", ...
    "not_executed_requires_physical_instrument", ...
    localRelativePath(runFolder, matPath), ...
        localFileSHA256(matPath), false, false, false, "PASS", ...
    'VariableNames', {'Direction','EndpointType','ArtifactScope','UEIndex', ...
    'ServingCell','GrantContextId','CompositeTransmitterWaveform','VSGImportScope', ...
    'Frame','Slot','SampleRateHz', ...
    'CenterFrequencyHz','SampleCount','PortCount','CapturePoint', ...
    'WaveformAuthority','CommonNormalizationFullScale','NormalizedPeak', ...
    'NormalizedRMS','WaveformSHA256','CanonicalCSV','CanonicalCSV_SHA256', ...
    'KeysightCSVPerPort','KeysightCSV_SHA256', ...
    'KeysightInt16PerPort','KeysightInt16SHA256','KeysightInt16ByteOrder', ...
    'KeysightInt16QuantizationScale','KeysightInt16PeakCode', ...
    'KeysightInt16ClippedComponentCount','KeysightInt16MaxComplexError', ...
    'KeysightVSAMATPerPort','KeysightVSAMATSHA256','KeysightVSAMATSchema', ...
    'PlaybackRepeatPolicy','PlaybackMinimum1024Satisfied', ...
    'PlaybackMultipleOf16Satisfied','PlaybackInstrumentTargets', ...
    'PhysicalInstrumentValidationStatus', ...
    'MATFile','MATFileSHA256', ...
    'ProxyUsed','FallbackFlag','PlaceholderFlag','CaptureStatus'});
manifestT = localReadTable(manifestPath);
if ~isempty(manifestT) && ismember("Direction", ...
        string(manifestT.Properties.VariableNames))
    manifestT(strcmpi(string(manifestT.Direction), direction),:) = [];
end
manifestT = localAppendCompat(manifestT, row);
manifestT = sortrows(manifestT, "Direction");
sixgr.util.csvWriteTable(manifestPath, manifestT);

artifacts = struct( ...
    "Ok", true, "Direction", direction, ...
    "CanonicalCSVPath", string(canonicalPath), ...
    "KeysightCSVPaths", keysightPaths, ...
    "KeysightInt16Paths", keysightWIQPaths, ...
    "KeysightVSAMATPaths", keysightVSAMATPaths, ...
    "MATPath", string(matPath), ...
    "ManifestPath", string(manifestPath), ...
    "ManifestTable", manifestT, ...
    "SampleCount", double(nSamples), "PortCount", double(nPorts), ...
    "SampleRateHz", sampleRateHz, ...
    "WaveformSHA256", metadata.WaveformSHA256);
end

function relative = localRelativePath(root, pathValue)
root = replace(string(root), "\", "/");
pathValue = replace(string(pathValue), "\", "/");
if startsWith(lower(pathValue), lower(root + "/"))
    relative = extractAfter(pathValue, strlength(root) + 1);
else
    relative = pathValue;
end
end

function hash = localFileSHA256(pathValue)
fid = fopen(char(string(pathValue)), "rb");
if fid < 0
    error("sixgr:truth:TxIQArtifactReadFailed", ...
        "Cannot read Tx-IQ artifact %s for hashing.", string(pathValue));
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
hash = lower(string(sixgr.util.sha256Hex(fread(fid, Inf, "*uint8"))));
end

function localAtomicInt16Write(pathValue, values, machineFormat)
pathValue = char(string(pathValue));
sixgr.util.ensureFolder(fileparts(pathValue));
tmpPath = char(string(tempname()) + ".wiq");
cleanupTmp = onCleanup(@() localDeleteIfExists(tmpPath)); %#ok<NASGU>
fid = fopen(tmpPath, "wb", char(string(machineFormat)));
if fid < 0
    error("sixgr:truth:KeysightInt16OpenFailed", ...
        "Cannot open temporary Keysight int16 waveform for writing.");
end
cleanupFid = onCleanup(@() fclose(fid));
count = fwrite(fid, values, "int16");
clear cleanupFid;
if count ~= numel(values)
    error("sixgr:truth:KeysightInt16ShortWrite", ...
        "Keysight int16 waveform wrote %d of %d components.", ...
        count, numel(values));
end
[ok,message,identifier] = copyfile(tmpPath,pathValue,"f");
if ~ok
    error("sixgr:truth:KeysightInt16PublishFailed", ...
        "Cannot publish Keysight int16 waveform (%s): %s", ...
        string(identifier), string(message));
end
info = dir(pathValue);
expectedBytes = 2 * numel(values);
if isempty(info) || double(info.bytes) ~= expectedBytes
    error("sixgr:truth:KeysightInt16SizeMismatch", ...
        "Published Keysight int16 waveform has %g bytes; expected %g.", ...
        localFileBytes(info), expectedBytes);
end
end

function bytes = localFileBytes(info)
if isempty(info)
    bytes = NaN;
else
    bytes = double(info(1).bytes);
end
end

function localDeleteIfExists(pathValue)
try
    if isfile(pathValue)
        delete(pathValue);
    end
catch
end
end

function hash = localComplexSHA256(value)
% Hash shape and the exact IEEE-754 real/imaginary sample payload. JSON
% encoders do not have a portable complex-number representation.
shapeBytes = reshape(typecast(uint64(size(value)), "uint8"), [], 1);
realBytes = reshape(typecast(double(real(value(:))), "uint8"), [], 1);
imagBytes = reshape(typecast(double(imag(value(:))), "uint8"), [], 1);
hash = lower(string(sixgr.util.sha256Hex( ...
    [shapeBytes; realBytes; imagBytes])));
end

function T = localReadTable(pathValue)
T = table();
if ~isfile(pathValue)
    return;
end
try
    T = sixgr.util.csvReadTable(pathValue, "TextType", "string");
catch
    T = table();
end
end

function out = localAppendCompat(a, b)
if isempty(a)
    out = b;
    return;
end
vars = union(string(a.Properties.VariableNames), ...
    string(b.Properties.VariableNames), "stable");
a = localEnsureVariables(a, vars);
b = localEnsureVariables(b, vars);
out = [a(:,cellstr(vars)); b(:,cellstr(vars))];
end

function T = localEnsureVariables(T, vars)
current = string(T.Properties.VariableNames);
for name = vars(:).'
    if ismember(name, current)
        continue;
    end
    T.(char(name)) = strings(height(T),1);
end
end
