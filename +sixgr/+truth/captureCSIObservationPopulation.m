function population=captureCSIObservationPopulation(state,cfg,slotIdx,configuredSNR)
%CAPTURECSIOBSERVATIONPOPULATION Freeze supplied context before CSI enqueue.
% This value boundary does NOT prove transmission, reception or noise power.
% queueSharedPeriodicCSIRS owns the actual shared-owner admission check.
% Missing component lifecycle stays missing; never infer IDs from a folder.
arguments
    state (1,1) struct
    cfg (1,1) struct
    slotIdx (1,1) double {mustBeInteger,mustBePositive}
    configuredSNR (1,1) double {mustBeReal,mustBeFinite}
end
owner=state.SharedWaveformStream;
queued=double(owner.Events.NextSampleIndex);
epoch=double(owner.Physical.ConfigurationEpoch);
fs=double(owner.SampleRateHz);
validateattributes(queued,{'double'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(epoch,{'double'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(fs,{'double'},{'scalar','real','finite','positive'});
fields=struct('RunFolder',localText(cfg,'run.rootRunFolder'), ...
    'RunID',localText(cfg,'run.runTag'),'RunTag',localText(cfg,'run.runTag'), ...
    'ExecutionID',localText(cfg,'run.executionID'), ...
    'ConfigHash',localText(cfg,'meta.configHash'), ...
    'ScenarioID',localText(cfg,'run.scenarioID'), ...
    'RandomSeed',localNumber(cfg,'run.seed'), ...
    'ChannelSeed',localNumber(cfg,'channel.seed'), ...
    'SweepPointIndex',localNumber(state,'CurrentSweepPointIndex'), ...
    'ConfiguredSNR_dB',configuredSNR);
for name=["RandomSeed","ChannelSeed","SweepPointIndex"]
    value=fields.(name);
    assert(isnan(value) || (value>=0 && value==fix(value)), ...
        'sixgr:truth:InvalidCSIObservationPopulation', ...
        'Supplied seeds/point indices must be nonnegative integers, or missing.');
end
population=struct('Version',"csi_observation_population/v1", ...
    'Source',"configured_queue_context_not_emission_proof", ...
    'Fields',fields, ...
    'Queue',struct('SourceSlot',slotIdx,'QueuedAtSample',queued, ...
    'ClockDomain',"shared_physical_sample_clock/v1", ...
    'PhysicalConfigurationEpoch',epoch,'SampleRateHz',fs), ...
    'ConfiguredSNRRole',"configured_operating_point_label_not_measured_SINR_or_thermal_noise_authority", ...
    'SeedRole',"configured_global_and_channel_seeds_not_executed_receiver_noise_stream_seed");
population.SHA256=string(sixgr.util.sha256Hex(jsonencode(population)));
end

function value=localText(input,path)
value=sixgr.util.structGet(input,path,"");
if isempty(value), value=""; return; end
assert(ischar(value) || isstring(value), ...
    'sixgr:truth:InvalidCSIObservationPopulation','Supplied lifecycle identity must be text.');
value=string(value);
assert(isscalar(value),'sixgr:truth:InvalidCSIObservationPopulation', ...
    'Supplied lifecycle identity must be scalar.');
if ismissing(value), value=""; end
end

function value=localNumber(input,path)
value=sixgr.util.structGet(input,path,NaN);
if isempty(value), value=NaN; return; end
assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
    (isfinite(value) || isnan(value)), ...
    'sixgr:truth:InvalidCSIObservationPopulation','Supplied population coordinates must be scalar or missing.');
value=double(value);
end
