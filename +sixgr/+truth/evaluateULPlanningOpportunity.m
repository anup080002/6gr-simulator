function [state,opportunity]=evaluateULPlanningOpportunity(state,cfg,decision,pending,sweepIndex,slotsPerPoint)
% Retain actual K2-engine decisions before queue/UE/HARQ admission.
% No receiver, future traffic, channel evolution or HARQ allocation executes.
assert(isstruct(decision)&&isscalar(decision)&&string(decision.Direction)=="UL", ...
    'sixgr:truth:InvalidULTimingEvidence','Require the actual UL timing decision.');
assert(string(decision.IndexConvention)=="zero_based", ...
    'sixgr:truth:InvalidULTimingEvidence','Timing-engine indices must remain zero-based.');
assert(isscalar(sweepIndex)&&isfinite(sweepIndex)&&sweepIndex>=1&&fix(sweepIndex)==sweepIndex && ...
    isscalar(slotsPerPoint)&&isfinite(slotsPerPoint)&&slotsPerPoint>=1&&fix(slotsPerPoint)==slotsPerPoint, ...
    'sixgr:truth:InvalidULPlanningHorizon','Require an explicit integer sweep horizon.');
controlSlot=double(state.CurrentSlot);
assert(double(decision.ControlAbsoluteSlot)==controlSlot-1, ...
    'sixgr:truth:ULTimingDecisionClockMismatch','Do not publish another control occasion as this decision.');
attempts=decision.DataAttempts;
previous=sixgr.util.structGet(state,'ULPlanningOpportunityTable',table());
sequence=height(previous)+1;
opportunity=struct('DecisionSequence',sequence,'SweepPointIndex',double(sweepIndex), ...
    'ConfiguredSNR_dB',double(sixgr.util.structGet(state,'CurrentSNR_dB',NaN)), ...
    'ControlSlot',controlSlot,'ControlAbsoluteSlot0Based',double(decision.ControlAbsoluteSlot), ...
    'SchedulingCCID',string(decision.SchedulingCCID),'ScheduledCCID',string(decision.ScheduledCCID), ...
    'SourceBWPID',string(decision.SourceBWPID),'TargetBWPID',string(decision.TargetBWPID), ...
    'ControlStartSymbol0Based',double(decision.ControlSymbolAllocation(1)), ...
    'ControlNumSymbols',double(decision.ControlSymbolAllocation(2)), ...
    'SweepStartSlot',(sweepIndex-1)*slotsPerPoint+1,'SweepEndSlot',sweepIndex*slotsPerPoint, ...
    'TimingEngineValid',logical(decision.Valid),'TimingEngineReason',string(decision.ReasonCode), ...
    'TimingSelectedK2',double(decision.K2),'TimingSelectedDataSlot',NaN, ...
    'TargetSlotHasUL',NaN,'ExistingQueuedGrantForTarget',NaN, ...
    'EvaluatedCandidateCount',numel(attempts),'EligibleForUEScheduling',false, ...
    'BlockReason',"timing_rejected:"+string(decision.ReasonCode), ...
    'SlotNumbering',"one_based_runtime_slots_with_explicit_zero_based_engine_control", ...
    'EvidenceRole',"control_time_timing_preflight_not_UE_admission_DCI_or_data_execution", ...
    'ValueSource',"TimingRelationEngine_and_current_pending_UL_grants");
if decision.Valid
    dueSlot=double(decision.DataAbsoluteSlot)+1;
    opportunity.TimingSelectedDataSlot=dueSlot;
    if ~(isfinite(dueSlot)&&dueSlot>=opportunity.SweepStartSlot&&dueSlot<=opportunity.SweepEndSlot)
        opportunity.BlockReason="target_outside_current_sweep_horizon";
    else
        % Same duplex availability boundary as the shared execution loop.
        duplex=sixgr.phy.frame.resolveDuplexMode(cfg);
        switch duplex
            case "FDD"
                allowUL=true;
            case "TDD"
                partition=sixgr.util.resolveTDDSlotPartition(cfg,dueSlot-1);
                allowUL=logical(partition.AllowUL);
            otherwise
                error('sixgr:truth:InvalidCoupledDuplexMode','Expected resolved FDD or TDD.');
        end
        opportunity.TargetSlotHasUL=double(allowUL);
        if ~allowUL
            opportunity.BlockReason="target_slot_has_no_UL_partition";
        else
            alreadyQueued=false;
            if isstruct(pending)&&~isempty(pending)
                slots=arrayfun(@sixgr.truth.runtimeULGrantSlot,pending(:));
                alreadyQueued=any(abs(slots-dueSlot)<1e-9);
            end
            opportunity.ExistingQueuedGrantForTarget=double(alreadyQueued);
            if alreadyQueued
                opportunity.BlockReason="target_already_has_queued_UL_grant";
            else
                opportunity.EligibleForUEScheduling=true;
                opportunity.BlockReason="";
            end
        end
    end
end
% This is one real preflight event even if no candidate or UE was admitted.
% It must never become a grant/TBS row or a successful PHY trial.
state.ULPlanningOpportunityTable=[previous;struct2table(opportunity)];
candidateRows=struct([]);
for k=1:numel(attempts)
    a=attempts(k);
    r=struct('DecisionSequence',sequence,'SweepPointIndex',double(sweepIndex), ...
        'ConfiguredSNR_dB',opportunity.ConfiguredSNR_dB,'ControlSlot',controlSlot, ...
        'CandidateOrdinal',k,'K2',double(a.K2),'TimingValid',logical(a.Valid), ...
        'ReasonCode',string(a.ReasonCode),'Status',string(a.Status), ...
        'SelectedByTimingEngine',logical(decision.Valid && a.Valid && ...
            double(a.TargetAbsoluteSlot)==double(decision.DataAbsoluteSlot) && ...
            double(a.K2)==double(decision.K2)), ...
        'TargetAbsoluteSlot0Based',a.TargetAbsoluteSlot, ...
        'SourceBWPID',string(sixgr.util.structGet(a,'SourceBWPID',"")), ...
        'TargetBWPID',string(sixgr.util.structGet(a,'TargetBWPID',"")), ...
        'SourceMu',double(sixgr.util.structGet(a,'SourceMu',NaN)), ...
        'TargetMu',double(sixgr.util.structGet(a,'TargetMu',NaN)), ...
        'TargetStartSymbol0Based',double(sixgr.util.structGet(a,'TargetStartSymbol',NaN)), ...
        'TargetNumSymbols',double(sixgr.util.structGet(a,'TargetNumSymbols',NaN)), ...
        'SourceTick',sixgr.util.structGet(a,'SourceTick',int64(-1)), ...
        'TargetTick',sixgr.util.structGet(a,'TargetTick',int64(-1)), ...
        'ProcessingGapTicks',sixgr.util.structGet(a,'ProcessingGapTicks',int64(-1)), ...
        'MinimumProcessingTicks',sixgr.util.structGet(a,'MinimumProcessingTicks',int64(-1)), ...
        'TimingAdvanceTicks',sixgr.util.structGet(a,'TimingAdvanceTicks',int64(-1)), ...
        'AvailabilityReasonCode',string(sixgr.util.structGet(a,'AvailabilityReasonCode',"")), ...
        'ObservedDirections',string(sixgr.util.structGet(a,'ObservedDirections',"")), ...
        'IndexConvention',"zero_based_engine_indices", ...
        'TickConvention',"AbsoluteTime_integer_ticks_negative_one_is_unresolved", ...
        'EvidenceRole',"actually_evaluated_configured_K2_not_all_possible_future_slots", ...
        'ValueSource',"TimingRelationEngine.DataAttempts");
    candidateRows=[candidateRows;r]; %#ok<AGROW> bounded by installed K2 list
end
if ~isempty(candidateRows)
    state.ULPlanningTimingCandidateTable=[sixgr.util.structGet( ...
        state,'ULPlanningTimingCandidateTable',table());struct2table(candidateRows)];
end
end
