classdef ReceivedMIBDelivery
% Receiver-owned retained BCH context. No PHY execution or TX-tree oracle.
% The binding joins original shared capture evidence; its hash is an
% integrity check, not an external cryptographic execution attestation.
methods (Static)
    function binding=bindCompleted(state,item,context,dl,decoderObservation)
        assert(isa(context,'sixgr.phy.broadcast.ReceivedMIBContext') && isscalar(context), ...
            'sixgr:truth:ReceivedMIBContextRequired','Retain the original accepted BCH context.');
        owner=localOwner(state); ue=localUE(state,item.UE);
        identity=owner.broadcastReceiveIdentity(ue);
        assert(string(item.Kind)=="PBCH" && state.CurrentServingIdx(ue)==identity.ServingCell && ...
            sixgr.util.structGet(item.Context,'ServingCell',NaN)==identity.ServingCell, ...
            'sixgr:truth:ReceivedMIBOwnerMismatch','Original acquisition must belong to this installed UE/cell.');
        cfg=item.Context.Prepared.ReceiverConfig;
        context.validate(cfg); d=context.Data;
        assert(d.GlobalCaptureEpochBound && d.OriginalStrictReceiverEvidenceOk && ...
            d.SampleRateHz==identity.SampleRateHz, ...
            'sixgr:truth:ReceivedMIBContextRequired','Runtime reuse requires a verified original typed capture.');
        [raw,decoded]=localObservation(owner,item,identity,decoderObservation);
        assert(decoded.sampleHash()==d.CaptureSampleSHA256 && ...
            decoded.StartSample==d.CaptureStartSample && decoded.EndSampleExclusive==d.CaptureEndSampleExclusive && ...
            decoded.NumReceiveAntennas==d.NumReceiveAntennas, ...
            'sixgr:truth:ReceivedMIBCaptureMismatch','The MIB must come from this exact original decoder input.');
        localTiming(dl,d);
        binding=identity;
        binding.ContractVersion="sixgr.truth.received_mib_delivery/v1";
        binding.Source="original_shared_receiver_BCH_context_not_SIB1_or_RRC";
        binding.Context=context;
        binding.ContextSHA256=context.SHA256;
        binding.AcquisitionConfigurationEpoch=d.ReceiverGeometry.ConfigurationEpoch;
        binding.ObservationID=string(item.ID);
        binding.CaptureStartSample=d.CaptureStartSample;
        binding.CaptureEndSampleExclusive=d.CaptureEndSampleExclusive;
        binding.NumReceiveAntennas=d.NumReceiveAntennas;
        binding.RawPostRFInputSHA256=string(raw.sampleHash());
        binding.DecoderInputSHA256=string(decoded.sampleHash());
        binding.BoundAtSample=owner.Events.NextSampleIndex;
        binding.ReceivedDLTimingReference=dl;
        binding.BindingSHA256=localBindingHash(binding);
        binding.GenerationID=binding.BindingSHA256;
        binding.Delivered=false;
        binding.DeliveredAvailableSample=NaN;
        binding.DeliverySlot=NaN;
        binding.DeliverySHA256="";
        sixgr.truth.ReceivedMIBDelivery.validate(binding,false);
    end

    function [state,installed,status]=deliver(state,binding)
        sixgr.truth.ReceivedMIBDelivery.validate(binding,false);
        installed=false; status="stale_receiver_or_acquisition";
        ue=localUE(state,binding.UEIndex); owner=localOwner(state);
        if ~localIdentity(state,binding) || string(state.CellAcquisitionState(ue))~="acquired"
            return;
        end
        now=localNow(state,owner);
        if now<binding.CaptureEndSampleExclusive
            status="awaiting_complete_capture_delivery"; return;
        end
        cfg=sixgr.truth.CoupledTruthRuntime.measurementConfigurationForUE(state,ue);
        binding.Context.validate(cfg);
        assert(state.LastSuccessfulPBCHSlotByUE(ue)==state.CurrentSlot, ...
            'sixgr:truth:ReceivedMIBAcquisitionDeliveryRequired', ...
            'Deliver retained MIB immediately after this original accepted acquisition.');
        values=sixgr.util.structGet(state,'ReceivedMIBByUE',cell(state.NumUsers,1));
        if numel(values)>=ue && ~isempty(values{ue})
            old=values{ue}; sixgr.truth.ReceivedMIBDelivery.validate(old,true);
            if old.BindingSHA256==binding.BindingSHA256
                installed=true; status="already_delivered_original_context"; return;
            end
            if old.PhysicalConfigurationEpoch==binding.PhysicalConfigurationEpoch && ...
                    old.CaptureEndSampleExclusive>=binding.CaptureEndSampleExclusive
                status="older_or_ambiguous_acquisition_capture"; return;
            end
        end
        binding.Delivered=true;
        binding.DeliveredAvailableSample=now;
        binding.DeliverySlot=double(state.CurrentSlot);
        binding.DeliverySHA256=localDeliveryHash(binding);
        values{ue,1}=binding; state.ReceivedMIBByUE=values;
        installed=true; status="delivered_original_received_MIB";
    end

    function [available,status,binding]=current(state,ue,cfg)
        available=false; status="no_delivered_received_MIB"; binding=[];
        ue=localUE(state,ue); owner=localOwner(state);
        values=sixgr.util.structGet(state,'ReceivedMIBByUE',{});
        if numel(values)<ue || isempty(values{ue}), return; end
        binding=values{ue}; sixgr.truth.ReceivedMIBDelivery.validate(binding,true);
        status="stale_receiver_or_acquisition";
        if ~localIdentity(state,binding) || string(state.CellAcquisitionState(ue))~="acquired" || ...
                state.LastSuccessfulPBCHSlotByUE(ue)~=binding.DeliverySlot
            return;
        end
        if nargin<3, cfg=sixgr.truth.CoupledTruthRuntime.measurementConfigurationForUE(state,ue); end
        geometry=sixgr.phy.broadcast.ReceivedMIBContext.receiverGeometry(cfg);
        if ~isequaln(geometry,binding.Context.Data.ReceiverGeometry) || ...
                cfg.phy.carrier.NCellID~=binding.Context.Data.NCellID
            status="changed_received_MIB_configuration"; return;
        end
        if localNow(state,owner)<binding.DeliveredAvailableSample
            status="received_MIB_not_yet_delivered"; return;
        end
        available=true; status="current_delivered_received_MIB";
    end

    function [accepted,status]=acceptedSI(state,ue,binding,result,item)
        sixgr.truth.ReceivedMIBDelivery.validate(binding,true);
        ue=localUE(state,ue); owner=localOwner(state);
        assert(item.UE==ue && ue==binding.UEIndex && string(item.Kind)=="SIB1" && ...
            isfield(item.Context,'ReceivedMIBBinding') && ...
            item.Context.ReceivedMIBBinding.BindingSHA256==binding.BindingSHA256 && ...
            item.Context.ReceivedMIBBinding.DeliverySHA256==binding.DeliverySHA256, ...
            'sixgr:truth:ReceivedMIBArmedContextMismatch','SI must retain the context frozen when its RX window was armed.');
        sixgr.truth.ReceivedMIBDelivery.validate(item.Context.ReceivedMIBBinding,true);
        identity=owner.broadcastReceiveIdentity(ue);
        [~,decoded]=localObservation(owner,item,identity,[]);
        assert(decoded.StartSample>=binding.DeliveredAvailableSample && ...
            result.PriorBCHContextSHA256==binding.ContextSHA256 && ...
            islogical(result.NewBCHReceptionAttempted) && isscalar(result.NewBCHReceptionAttempted) && ~result.NewBCHReceptionAttempted && ...
            result.SIB1CaptureStartSample==decoded.StartSample && ...
            result.SIB1AvailableCaptureSamples==decoded.EndSampleExclusive-decoded.StartSample, ...
            'sixgr:truth:ReceivedMIBSICaptureMismatch','SI result must retain the original later capture and armed MIB context.');
        [accepted,status]=sixgr.truth.ReceivedMIBDelivery.validateSICaptureProjection( ...
            binding.Context.Data,result,decoded);
        if ~accepted, return; end
        [accepted,status,current]=sixgr.truth.ReceivedMIBDelivery.current(state,ue);
        if ~accepted, return; end
        if current.GenerationID~=binding.GenerationID
            accepted=false; status="retired_acquisition_generation"; return;
        end
        if localNow(state,owner)<decoded.EndSampleExclusive
            accepted=false; status="SI_result_not_yet_delivered"; return;
        end
        status="current_generation_received_SI";
    end

    function [observed,status]=validateSICaptureProjection(data,result,decoded)
        % Pure operand check, NOT proof of physical execution or authority.
        % acceptedSI first authenticates the whole original completed buffer
        % and immutable received context. The receiver hashes ONLY its slot
        % crop, which need not fill a prefixed/tail-extended capture.
        observed=false; status="SI_reception_not_attempted";
        assert(isstruct(data) && isscalar(data) && isstruct(result) && isscalar(result) && ...
            all(isfield(data,{'ReceiverGeometry','SampleRateHz','NumReceiveAntennas', ...
            'AbsoluteFrameNumber','ReceivedFrameOriginSample'})) && ...
            all(isfield(result,{'SIB1ReceptionAttempted','SIB1ObservationComplete', ...
            'SIB1CaptureStartSample','SIB1AvailableCaptureSamples'})) && ...
            isa(decoded,'sixgr.phy.waveform.WaveformObservationBuffer') && isscalar(decoded) && ...
            decoded.isComplete(), ...
            'sixgr:truth:ReceivedMIBSICaptureMismatch','Use the complete decoder buffer and original crop operands.');
        for name=["SIB1ReceptionAttempted","SIB1ObservationComplete"]
            assert(islogical(result.(name)) && isscalar(result.(name)), ...
                'sixgr:truth:ReceivedMIBSICaptureMismatch','SI observation flags must be scalar logical values.');
        end
        assert(isa(data.SampleRateHz,'double') && isreal(data.SampleRateHz) && ...
            isscalar(data.SampleRateHz) && isfinite(data.SampleRateHz) && data.SampleRateHz>0 && ...
            decoded.SampleRateHz==data.SampleRateHz && decoded.NumReceiveAntennas==data.NumReceiveAntennas && ...
            result.SIB1CaptureStartSample==decoded.StartSample && ...
            result.SIB1AvailableCaptureSamples==decoded.EndSampleExclusive-decoded.StartSample, ...
            'sixgr:truth:ReceivedMIBSICaptureMismatch','SI whole-capture clocks and receive columns changed.');
        if ~result.SIB1ReceptionAttempted
            assert(~result.SIB1ObservationComplete, ...
                'sixgr:truth:ReceivedMIBSICaptureMismatch','An unattempted SI must not claim a completed decoder slot.');
            return; % No associated Type0/incomplete capture: no CRC trial.
        end
        assert(result.SIB1ObservationComplete && ...
            all(isfield(result,{'SIB1AbsoluteSlot','SIB1ObservationStartSample', ...
            'SIB1ObservationEndSampleExclusive','SIB1ObservationSampleDomain','SIB1InputSampleSHA256'})), ...
            'sixgr:truth:ReceivedMIBSICaptureMismatch','An attempted SI needs its complete original slot projection.');
        localInteger(data.AbsoluteFrameNumber); localInteger(result.SIB1AbsoluteSlot);
        localInteger(result.SIB1ObservationStartSample); localInteger(result.SIB1ObservationEndSampleExclusive);
        origin=data.ReceivedFrameOriginSample;
        assert(isa(origin,'double') && isreal(origin) && isscalar(origin) && isfinite(origin) && ...
            abs(origin)<=flintmax && origin==fix(origin), ...
            'sixgr:truth:ReceivedMIBSICaptureMismatch','Use the original exact measured frame origin.');
        geometry=data.ReceiverGeometry;
        spec=sixgr.phy.frame.NumerologyCatalog.resolve(geometry.SubcarrierSpacing, ...
            geometry.CyclicPrefix,'generic_waveform_test','');
        assert(data.AbsoluteFrameNumber<=flintmax/spec.SlotsPerFrame, ...
            'sixgr:truth:ReceivedMIBSICaptureMismatch','Received radio frame is outside exact clock range.');
        relativeSlot=result.SIB1AbsoluteSlot-data.AbsoluteFrameNumber*spec.SlotsPerFrame;
        localInteger(relativeSlot);
        assert(relativeSlot<flintmax,'sixgr:truth:ReceivedMIBSICaptureMismatch','SI exclusive slot must remain exact.');
        first=origin+sixgr.phy.frame.slotStartSample(geometry,relativeSlot,data.SampleRateHz);
        stop=origin+sixgr.phy.frame.slotStartSample(geometry,relativeSlot+1,data.SampleRateHz);
        localInteger(first); localInteger(stop);
        a=result.SIB1ObservationStartSample; b=result.SIB1ObservationEndSampleExclusive;
        assert(first<stop && first>=decoded.StartSample && stop<=decoded.EndSampleExclusive && ...
            a==first-decoded.StartSample && b==stop-decoded.StartSample && ...
            isstring(result.SIB1ObservationSampleDomain) && isscalar(result.SIB1ObservationSampleDomain) && ...
            result.SIB1ObservationSampleDomain=="relative_to_original_received_capture_start_zero_based" && ...
            isstring(result.SIB1InputSampleSHA256) && isscalar(result.SIB1InputSampleSHA256), ...
            'sixgr:truth:ReceivedMIBSICaptureMismatch','SI crop must match its original received radio-slot mapping.');
        samples=decoded.readComplete();
        digest=sixgr.phy.waveform.WaveformHash.runtimeArray(samples(a+1:b,:));
        assert(result.SIB1InputSampleSHA256==digest, ...
            'sixgr:truth:ReceivedMIBSICaptureMismatch','The decoded SI input hash must match the original slot crop, not the whole capture.');
        observed=true; status="original_SI_slot_projection_matched";
    end

    function validate(binding,requireDelivered)
        assert(islogical(requireDelivered) && isscalar(requireDelivered) && ...
            isstruct(binding) && isscalar(binding) && ...
            all(isfield(binding,{'ContractVersion','Source','Context','ContextSHA256','UEIndex','ServingCell', ...
            'LinkID','ReceiverID','TransmitterID','PhysicalConfigurationEpoch','AcquisitionConfigurationEpoch', ...
            'SampleRateHz','ObservationID','CaptureStartSample','CaptureEndSampleExclusive','NumReceiveAntennas', ...
            'RawPostRFInputSHA256','DecoderInputSHA256','BoundAtSample','ReceivedDLTimingReference', ...
            'BindingSHA256','GenerationID','Delivered','DeliveredAvailableSample','DeliverySlot','DeliverySHA256'})), ...
            'sixgr:truth:InvalidReceivedMIBDelivery','Retain the complete original MIB delivery binding.');
        assert(binding.ContractVersion=="sixgr.truth.received_mib_delivery/v1" && ...
            binding.Source=="original_shared_receiver_BCH_context_not_SIB1_or_RRC" && ...
            isa(binding.Context,'sixgr.phy.broadcast.ReceivedMIBContext') && isscalar(binding.Context), ...
            'sixgr:truth:InvalidReceivedMIBDelivery','Wrong retained MIB contract.');
        d=binding.Context.Data;
        for name=["UEIndex","ServingCell","PhysicalConfigurationEpoch","AcquisitionConfigurationEpoch", ...
                "CaptureStartSample","CaptureEndSampleExclusive","NumReceiveAntennas","BoundAtSample"]
            localInteger(binding.(name));
        end
        assert(binding.UEIndex>=1 && binding.ServingCell>=1 && binding.NumReceiveAntennas>=1 && ...
            binding.CaptureStartSample<binding.CaptureEndSampleExclusive && ...
            binding.CaptureEndSampleExclusive<=binding.BoundAtSample && ...
            binding.ContextSHA256==binding.Context.SHA256 && localHash(d)==binding.ContextSHA256 && ...
            binding.DecoderInputSHA256==d.CaptureSampleSHA256 && binding.CaptureStartSample==d.CaptureStartSample && ...
            binding.CaptureEndSampleExclusive==d.CaptureEndSampleExclusive && binding.SampleRateHz==d.SampleRateHz && ...
            binding.NumReceiveAntennas==d.NumReceiveAntennas && d.GlobalCaptureEpochBound && ...
            binding.AcquisitionConfigurationEpoch==d.ReceiverGeometry.ConfigurationEpoch && ...
            binding.BindingSHA256==localBindingHash(binding) && binding.GenerationID==binding.BindingSHA256 && ...
            islogical(binding.Delivered) && isscalar(binding.Delivered), ...
            'sixgr:truth:InvalidReceivedMIBDelivery','Original context, receiver, clock or binding digest changed.');
        localTiming(binding.ReceivedDLTimingReference,d);
        if binding.Delivered
            localInteger(binding.DeliveredAvailableSample); localInteger(binding.DeliverySlot);
            assert(binding.DeliverySlot>=1 && binding.DeliveredAvailableSample>=binding.CaptureEndSampleExclusive && ...
                binding.DeliverySHA256==localDeliveryHash(binding), ...
                'sixgr:truth:InvalidReceivedMIBDelivery','Original delivery clock or digest changed.');
        else
            assert(~requireDelivered && isequaln(binding.DeliveredAvailableSample,NaN) && ...
                isequaln(binding.DeliverySlot,NaN) && binding.DeliverySHA256=="", ...
                'sixgr:truth:ReceivedMIBNotDelivered','Undelivered context cannot arm a later SI receiver.');
        end
    end
end
end

function owner=localOwner(state)
owner=sixgr.util.structGet(state,'SharedWaveformStream',[]);
assert(isa(owner,'sixgr.truth.CoupledWaveformStream') && isscalar(owner), ...
    'sixgr:truth:ReceivedMIBSharedOwnerRequired','Use the original shared receive owner.');
end
function ue=localUE(state,ue)
localInteger(ue); assert(ue>=1 && ue<=state.NumUsers,'sixgr:truth:ReceivedMIBOwnerMismatch','Unknown UE.');
end
function localInteger(v)
assert(isa(v,'double') && isreal(v) && isscalar(v) && isfinite(v) && v>=0 && v<=flintmax && v==fix(v), ...
    'sixgr:truth:InvalidReceivedMIBDelivery','Identity/clock must be an exact nonnegative double integer.');
end
function now=localNow(state,owner)
c=sixgr.phy.grid.makeCarrier(state.CfgMobility);
now=sixgr.phy.frame.slotStartSample(c,state.CurrentSlot-1,owner.SampleRateHz);
localInteger(now);
assert(now<=owner.Events.NextSampleIndex,'sixgr:truth:ReceivedMIBFutureDelivery','The physical owner has not reached this delivery boundary.');
end
function tf=localIdentity(state,b)
owner=localOwner(state); id=owner.broadcastReceiveIdentity(b.UEIndex);
tf=state.CurrentServingIdx(b.UEIndex)==b.ServingCell;
for name=string(fieldnames(id)).', tf=tf && isequaln(id.(name),b.(name)); end
end
function localTiming(dl,d)
assert(isstruct(dl) && isscalar(dl) && ...
    string(sixgr.util.structGet(dl,'Source',''))=="received_SSB_timing_and_decoded_BCH" && ...
    sixgr.util.structGet(dl,'SampleRateHz',NaN)==d.SampleRateHz && ...
    sixgr.util.structGet(dl,'ObservationStartSample',NaN)==d.CaptureStartSample && ...
    sixgr.util.structGet(dl,'AvailableAtSample',NaN)==d.CaptureEndSampleExclusive && ...
    sixgr.util.structGet(dl,'NCellID',NaN)==d.NCellID && sixgr.util.structGet(dl,'SSBIndex',NaN)==d.SSBIndex && ...
    sixgr.util.structGet(dl,'ReceivedSFN',NaN)==d.ReceivedSFN && ...
    sixgr.util.structGet(dl,'ReceivedHalfFrame',NaN)==d.HalfFrame && ...
    sixgr.util.structGet(dl,'AbsoluteFrameNumber',NaN)==d.AbsoluteFrameNumber, ...
    'sixgr:truth:ReceivedMIBTimingMismatch','Keep original received DL timing, not a new SI or configured timing reference.');
end
function [raw,decoded]=localObservation(owner,item,id,provided)
owner.validateCompletedBroadcastObservation(item);
planes=item.Planes; k=find(string({planes.ReceiverID})==id.ReceiverID+":post_rf");
assert(isscalar(k),'sixgr:truth:ReceivedMIBOwnerMismatch','Exactly one original post-RF receiver plane is required.');
raw=planes(k).Observation; segments=planes(k).Segments;
assert(isa(raw,'sixgr.phy.waveform.WaveformObservationBuffer') && raw.isComplete() && ...
    raw.SampleRateHz==id.SampleRateHz && raw.EndSampleExclusive<=owner.Events.NextSampleIndex && ~isempty(segments), ...
    'sixgr:truth:ReceivedMIBCaptureMismatch','Use the completed original physical capture.');
previous=raw.StartSample;
for j=1:numel(segments)
    s=segments{j}; e=s.Execution;
    assert(s.StartSample<=previous && s.EndSampleExclusive>previous && ...
        (j==1 || s.StartSample==previous) && e.ConfigurationEpoch==id.PhysicalConfigurationEpoch && ...
        e.SampleRateHz==id.SampleRateHz && e.StartSample==s.StartSample && e.EndSampleExclusive==s.EndSampleExclusive && ...
        string(e.Source)=="composed_tx_retained_rf_per_link_channel_sum_receiver_noise_rf" && ...
        any(string({e.RX.ID})==id.ReceiverID), ...
        'sixgr:truth:ReceivedMIBExecutionMismatch','Original receive execution must cover the capture without gaps.');
    links=e.Links(string({e.Links.ID})==id.LinkID);
    dl=isscalar(links) && string(links.TX)==id.TransmitterID && string(links.RX)==id.ReceiverID;
    ul=isscalar(links) && string(links.TX)=="ue_"+id.UEIndex && ...
        string(links.RX)=="gnb_"+id.ServingCell+"_rx";
    assert(dl || ul,'sixgr:truth:ReceivedMIBOwnerMismatch', ...
        'Retain this installed link, including its original TDD reversals during a long capture.');
    trace=owner.Events.ExecutionTrace;
    matched=false;
    for z=numel(trace):-1:1
        t=trace{z};
        if t.StartSample==s.StartSample && t.EndSampleExclusive==s.EndSampleExclusive
            % Reference tensor retention differs by plane. Compare original
            % physical receiver/link operands, not optional scoring arrays.
            matched=isequaln(t.Execution.RX,e.RX) && isequaln(t.Execution.Links,e.Links) && ...
                t.Execution.ConfigurationEpoch==e.ConfigurationEpoch; break;
        end
    end
    assert(matched,'sixgr:truth:ReceivedMIBExecutionMismatch','Capture execution is not retained by this original event owner.');
    previous=s.EndSampleExclusive;
end
assert(previous>=raw.EndSampleExclusive,'sixgr:truth:ReceivedMIBExecutionMismatch','Incomplete original capture evidence.');
[decoded,~]=sixgr.phy.rx.compensateReceivedAGC(raw,segments,id.ReceiverID);
if ~isempty(provided)
    assert(isa(provided,'sixgr.phy.waveform.WaveformObservationBuffer') && provided.isComplete() && ...
        provided.StartSample==decoded.StartSample && provided.EndSampleExclusive==decoded.EndSampleExclusive && ...
        provided.SampleRateHz==decoded.SampleRateHz && provided.sampleHash()==decoded.sampleHash(), ...
        'sixgr:truth:ReceivedMIBCaptureMismatch','Use the exact original gain-compensated decoder input.');
    decoded=provided;
end
end
function hash=localBindingHash(b)
names={'ContractVersion','Source','ContextSHA256','UEIndex','ServingCell','LinkID','ReceiverID','TransmitterID', ...
    'PhysicalConfigurationEpoch','AcquisitionConfigurationEpoch','SampleRateHz','ObservationID', ...
    'CaptureStartSample','CaptureEndSampleExclusive','NumReceiveAntennas','RawPostRFInputSHA256', ...
    'DecoderInputSHA256','BoundAtSample','ReceivedDLTimingReference'};
r=struct(); for k=1:numel(names), r.(names{k})=b.(names{k}); end
hash=localHash(r);
end
function hash=localDeliveryHash(b)
hash=localHash(struct('BindingSHA256',b.BindingSHA256,'GenerationID',b.GenerationID, ...
    'Delivered',b.Delivered,'DeliveredAvailableSample',b.DeliveredAvailableSample,'DeliverySlot',b.DeliverySlot));
end
function hash=localHash(v)
hash=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(v))));
end
