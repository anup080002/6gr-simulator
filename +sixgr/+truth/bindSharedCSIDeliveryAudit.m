function state=bindSharedCSIDeliveryAudit(state,item)
% Post-publication audit only. Never supply TX bits to a receiver/scheduler.
c=item.Context;
if ~isfield(c,'Prepared') || ...
        ~isa(c.Prepared,'sixgr.link.PreparedUplinkControlTransmission')
    return; % A receive-only obligation is not evidence of emitted CSI.
end
T=sixgr.util.structGet(state,'SharedGNBCSIReportTable',table());
if isempty(T), return; end
hit=find(string(T.ObservationID)==string(item.ID));
if isempty(hit), return; end % HARQ/SR-only reception has no CSI report.
assert(isscalar(hit) && T.UEIndex(hit)==item.UE && ...
    string(T.CSIUCIChannel(hit))=="PUCCH", ...
    'sixgr:truth:AmbiguousCSIDeliveryObservation', ...
    'Bind the private audit to exactly one independently completed CSI reception.');
identity=sixgr.truth.preparedPUCCHTransmissionIdentity(c.Prepared,item.UE,item.ID);
ledger=sixgr.util.structGet(state,'SharedPUCCHTXLedger',{});
j=find(cellfun(@(r)r.Identity.TransmissionID==identity.TransmissionID,ledger));
records=state.SharedWaveformStream.PUCCHTransmissions;
k=find(arrayfun(@(r)r.Identity.TransmissionID==identity.TransmissionID,records));
assert(isscalar(j) && isscalar(k) && ...
    isequaln(ledger{j}.Identity,identity) && isequaln(records(k).Identity,identity) && ...
    ledger{j}.FirstActiveSample==records(k).FirstActiveSample && ...
    ledger{j}.CommittedAtSample==records(k).CommittedAtSample && ...
    isequaln(ledger{j}.WaveformToElementMatrix,records(k).WaveformToElementMatrix) && ...
    identity.EndSampleExclusive<=state.SharedWaveformStream.Events.NextSampleIndex, ...
    'sixgr:truth:CSIDeliveryEmissionNotExecuted', ...
    'Require matching physical-owner and MAC emission receipts, not preparation alone.');
token=sixgr.truth.buildCSIDeliveryAudit(table2struct(T(hit,:)),c.Prepared,ledger{j}, ...
    c.Config.phy.csi.reportConfiguration);
if ~ismember('CSIDeliveryAuditJSON',T.Properties.VariableNames)
    T.CSIDeliveryAuditJSON=repmat("",height(T),1);
end
assert(strlength(T.CSIDeliveryAuditJSON(hit))==0, ...
    'sixgr:truth:DuplicateCSIDeliveryAudit','Attach the exact emission audit once.');
T.CSIDeliveryAuditJSON(hit)=token;
state.SharedGNBCSIReportTable=T;
end
