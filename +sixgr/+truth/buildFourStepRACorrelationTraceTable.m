function T = buildFourStepRACorrelationTraceTable(ra, prachRow, cfg, snr_dB, trialIdx)
% Exact measured Msg1 trace and per-target outcome, not an H0 campaign.
trace = sixgr.util.structGet(ra, "Msg1DetectionTrace", struct());
lags = double(sixgr.util.structGet(trace, "LagSamples", zeros(0, 1)));
corrAbs = double(sixgr.util.structGet(trace, "CorrelationAbs", zeros(0, 1)));
lags = lags(:);
corrAbs = corrAbs(:);
assert(numel(lags)==numel(corrAbs),'sixgr:truth:PRACHTraceSampleMismatch', ...
    'Every retained correlation sample requires its matching measured lag.');
n = numel(lags);
if n < 1
    T = table();
    return;
end
lags = lags(1:n);
corrAbs = corrAbs(1:n);
valid = isfinite(lags) & isfinite(corrAbs);
lags = lags(valid);
corrAbs = corrAbs(valid);
n = numel(lags);
if n < 1
    T = table();
    return;
end
msg1Tx = sixgr.util.structGet(ra, "Msg1Tx", struct());
sampleRateHz = double(sixgr.util.structGet(msg1Tx, "SampleRate_Hz", ...
    sixgr.util.structGet(msg1Tx, "PRACHRuntimeConfig.SampleRate_Hz", NaN)));
if ~(isfinite(sampleRateHz) && sampleRateHz > 0)
    error("sixgr:truth:MissingFourStepRACorrelationSampleRate", ...
        "Runtime Msg1 correlation trace requires its actual waveform sample rate.");
end
threshold = double(sixgr.util.structGet(trace, "Threshold", ...
    sixgr.util.structGet(ra, "PreambleDetectionThreshold", NaN)));
noiseFloor = double(sixgr.util.structGet(trace, "NoiseFloor", ...
    sixgr.util.structGet(ra, "Msg1PDPAverageNoiseFloor", NaN)));
peakLag = double(sixgr.util.structGet(trace, "PeakLagSamples", ...
    sixgr.util.structGet(ra, "Msg1DetectorPeakLagSamples", NaN)));
detected = localOutcome(sixgr.util.structGet(ra,"PreambleDetected", ...
    sixgr.util.structGet(prachRow,"DetectionSuccess",NaN)));
% These per-target outcomes cannot be inferred from any-candidate detection.
falseAlarm = localOutcome(sixgr.util.structGet(prachRow,"FalseAlarm",NaN));
missed = localOutcome(sixgr.util.structGet(prachRow,"MissedDetection",NaN));
detectionResult = repmat("unknown", n, 1);
if falseAlarm==1
    detectionResult(:) = "false_alarm";
elseif missed==1
    detectionResult(:) = "missed_detection";
elseif detected==1
    detectionResult(:) = "detected";
elseif detected==0
    detectionResult(:) = "no_detection";
end
seed = round(double(sixgr.util.structGet(cfg, "run.seed", ...
    sixgr.util.structGet(cfg, "run_control.seed", 1)))) + round(double(trialIdx)) - 1;
T = table( ...
    repmat(double(trialIdx), n, 1), ...
    repmat(double(sixgr.util.structGet(ra, "PreambleIndexDetected", NaN)), n, 1), ...
    repmat(double(sixgr.util.structGet(prachRow, "PRACHRootSequenceIndex", NaN)), n, 1), ...
    repmat(string(sixgr.util.structGet(prachRow, "PRACHRestrictedSetType", "")), n, 1), ...
    repmat(double(sixgr.util.structGet(prachRow, "PRACHNCS", NaN)), n, 1), ...
    repmat(double(sixgr.util.structGet(prachRow, "PRACHZeroCorrelationZone", NaN)), n, 1), ...
    lags, lags ./ sampleRateHz .* 1e6, corrAbs, ...
    repmat(threshold, n, 1), repmat(noiseFloor, n, 1), ...
    repmat(peakLag, n, 1), ...
    repmat(sixgr.truth.receivedRARTimingOnTraceClock(ra, sampleRateHz), n, 1), ...
    detectionResult, repmat(falseAlarm, n, 1), repmat(missed, n, 1), ...
    repmat(double(snr_dB), n, 1), ...
    repmat(double(sixgr.util.structGet(ra, "PRACHFrequencyEstimate_Hz", NaN)), n, 1), ...
    repmat(double(seed), n, 1), repmat("real_lls_evidence", n, 1), ...
    'VariableNames', {'trial_id','preamble_index','root_sequence_index', ...
    'restricted_set_type','n_cs','zero_correlation_zone_config', ...
    'lag_samples','lag_us','correlation_abs','threshold','noise_floor', ...
    'peak_lag_samples','timing_advance_samples','detection_result', ...
    'false_alarm','missed_detection','snr_db','cfo_hz','seed','truth_status'});
T.noise_floor_estimator=repmat(string(sixgr.util.structGet(trace,"NoiseFloorEvidence.Estimator","")),n,1);
T.noise_floor_definition=repmat(string(sixgr.util.structGet(trace,"NoiseFloorEvidence.Definition","")),n,1);
T.noise_floor_status=repmat(string(sixgr.util.structGet(trace,"NoiseFloorEvidence.Status","")),n,1);
T.noise_floor_pair_count=repmat(double(sixgr.util.structGet(trace,"NoiseFloorEvidence.PairCount",NaN)),n,1);
for pair=["trace_scope","TraceStatus"; "detector_backend","DetectorBackend"; ...
        "lag_reference","LagReference"; "threshold_source","ThresholdSource"; ...
        "metric_domain","MetricDomain"; "decision_timing_reference","DecisionTimingReference"].'
    T.(pair(1))=repmat(string(sixgr.util.structGet(trace,pair(2),"")),n,1);
end
for pair=["detector_input_start_offset_samples","DetectorInputStartOffsetSamples"; ...
        "raw_timing_offset_samples","RawTimingOffsetSamples"; ...
        "propagation_timing_offset_samples","PropagationTimingOffsetSamples"; ...
        "implementation_filter_delay_samples","ImplementationFilterDelay_samples"; ...
        "decision_threshold","DecisionThreshold"; "decision_peak_metric","DecisionPeakMetric"; ...
        "decision_peak_lag_samples","DecisionPeakLagSamples"; ...
        "candidate_peak_lower_tail_median","CandidatePeakLowerTailMedian"; ...
        "noise_floor_normalization","NoiseFloorEvidence.Normalization"; ...
        "noise_floor_sample_variance","NoiseFloorEvidence.SampleEquivalentVariance"; ...
        "noise_floor_reference_energy","NoiseFloorEvidence.ReferenceEnergy"; ...
        "noise_floor_received_energy","NoiseFloorEvidence.OccupiedReceivedEnergy"; ...
        "noise_floor_useful_start_sample0","NoiseFloorEvidence.UsefulStartSample0"; ...
        "noise_floor_nfft","NoiseFloorEvidence.NFFT"; ...
        "noise_floor_repetitions","NoiseFloorEvidence.Repetitions"].'
    T.(pair(1))=repmat(double(sixgr.util.structGet(trace,pair(2),NaN)),n,1);
end
for pair=["sweep_point_index","SweepPointIndex"; "configured_snr_db","ConfiguredSNR_dB"; ...
        "ue_index","UEIndex"; "cell_id","CellID"; "source_slot_1based","Slot"; ...
        "target_preamble_index","PreambleIndex"].'
    T.(pair(1))=repmat(double(sixgr.util.structGet(prachRow,pair(2),NaN)),n,1);
end
T.sample_rate_hz=repmat(sampleRateHz,n,1);
T.false_alarm_classification=repmat(string(sixgr.util.structGet(prachRow,"FalseAlarmClassification","")),n,1);
T.detection_population_scope=repmat(string(sixgr.util.structGet(prachRow,"DetectionPopulationScope","")),n,1);
end

function value=localOutcome(value)
assert((islogical(value)||isnumeric(value)) && isreal(value) && isscalar(value) && ...
    (isnan(value)||any(value==[0 1])), 'sixgr:truth:InvalidPRACHTraceOutcome', ...
    'Detection outcomes must be measured true/false or explicitly unknown.');
value=double(value);
end
