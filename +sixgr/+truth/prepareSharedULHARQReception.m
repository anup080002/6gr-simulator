function [token,prior]=prepareSharedULHARQReception(state,cfg,grant,observation)
% Bind receiver state to an actually transmitted gNB command and completed
% capture. Caller supplies its shared-owner observation, never a UE TB.
owner=state.SharedWaveformStream;
binding=sixgr.truth.puschUCIObservationBinding(grant,observation);
assert(double(grant.TimingDecision.DataAbsoluteSlot)+1>= ...
    sixgr.util.structGet(state,'SweepPointStartSlot',1), ...
    'sixgr:truth:PreviousSweepULHARQReception','A censored earlier-point observation cannot populate fresh receiver soft state.');
assert(observation.SampleRateHz==owner.SampleRateHz && ...
    observation.EndSampleExclusive<=owner.Events.NextSampleIndex, ...
    'sixgr:truth:ULHARQReceiveAttemptClock','Require completed same-clock reception.');
[key,identity]=sixgr.truth.scheduledULHARQReceiverKey(cfg,grant);
commands=owner.readTransmittedULControls(grant.UEIndex,double(grant.Slot));
hit=find(cellfun(@(r)r.Binding.GrantContextID==string(grant.PHYGrant.GrantContextId),commands));
assert(isscalar(hit),'sixgr:truth:ULHARQScheduledCommandRequired','Retain the unique physical gNB UL command.');
command=commands{hit}; scheduled=command.Binding.Grant;
assert(sixgr.truth.scheduledULHARQReceiverKey(cfg,scheduled)==key && ...
    isequaln(scheduled.DCI.Bits,grant.DCI.Bits) && ...
    isequaln(scheduled.TimingDecision,grant.TimingDecision), ...
    'sixgr:truth:ULHARQScheduledCommandMismatch','UE metadata cannot replace the scheduled receive process or allocation.');
scope=rmfield(identity,{'NDI','NDIEpoch'});
attempt=struct('ScopeKey',"gNB-UL-process-"+sixgr.phy.pucch.PUCCHUtil.hash(scope), ...
    'ReceiverKey',key,'NDIEpoch',identity.NDIEpoch, ...
    'DataAbsoluteSlot',double(grant.TimingDecision.DataAbsoluteSlot), ...
    'ObservationID',binding.ObservationID,'GrantContextID',string(grant.PHYGrant.GrantContextId), ...
    'CommandObservationID',string(command.ObservationID),'StartSample',observation.StartSample, ...
    'EndSampleExclusive',observation.EndSampleExclusive,'SampleRateHz',observation.SampleRateHz, ...
    'AvailableAtSample',owner.Events.NextSampleIndex);
[~,prior,token]=sixgr.truth.resolveULHARQReceiverState( ...
    sixgr.util.structGet(state,'SharedGNBULHARQReceivers',{}),attempt);
end
