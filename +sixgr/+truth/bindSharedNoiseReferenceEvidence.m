function T=bindSharedNoiseReferenceEvidence(T,planes)
% Post-reception noise-injection ledger, never a receiver SINR/RSRP estimate.
% Read scalar metadata only: no IQ reload, noise redraw or channel execution.
assert(istable(T) && height(T)>0,'sixgr:truth:NoiseReferenceTrialScope', ...
    'Bind completed receiver rows, not placeholder trials.');
ids=string({planes.ReceiverID}); selected=find(endsWith(ids,':post_rf'));
assert(isscalar(selected),'sixgr:truth:NoiseReferenceReceiverScope', ...
    'Exactly one received endpoint is required.');
plane=planes(selected); observation=plane.Observation;
receiver=extractBefore(ids(selected),':post_rf');
segments=plane.Segments;
assert(observation.isComplete() && ~isempty(segments), ...
    'sixgr:truth:NoiseReferenceIncompleteObservation','Retain the complete executed capture.');
numericFields=["InjectedNoiseVariance","NoiseStreamSeed", ...
    "RequestedAWGNReferenceSNR_dB","SignalEnergyPerOccupiedRE", ...
    "ReferenceAWGNGridNoiseVariance","ReferenceAWGNSampleNoiseVariance", ...
    "SampleToGridNoiseVarianceGain","AppliedAWGNSNR_dB", ...
    "ThermalSampleNoiseBandwidth_Hz","ThermalNoisePSD_mWPerHz"];
textFields=["InjectedNoiseVarianceDomain","NoiseOperatingMode", ...
    "NoiseVarianceSource","AWGNReferenceEnergySource","SharedNoiseCalibrationSource", ...
    "AppliedAWGNSNRSource","AppliedAWGNSNRValueRole","WaveformAmplitudeUnit"];
fields=[numericFields textFields];
records=cell(numel(segments),1); present=false(numel(segments),1);
intervals=zeros(numel(segments),2);
for k=1:numel(segments)
    e=segments{k}.Execution;
    nodes=e.RX; node=nodes(string({nodes.ID})==receiver);
    assert(isscalar(node),'sixgr:truth:NoiseReferenceReceiverScope', ...
        'Do not borrow another endpoint''s noise calibration.');
    intervals(k,:)=[e.StartSample e.EndSampleExclusive];
    r=node.Replay;
    present(k)=any(isfield(r,["InjectedNoiseVariance","RequestedAWGNReferenceSNR_dB", ...
        "ReferenceAWGNGridNoiseVariance","SharedNoiseCalibrationSource"]));
    if ~present(k), continue; end % Pure RF-component tests have no noise owner.
    assert(all(isfield(r,fields)),'sixgr:truth:IncompleteNoiseReference', ...
        'A declared physical noise execution must retain its complete calibration.');
    record=struct();
    for field=numericFields
        value=r.(field);
        assert(isnumeric(value) && isreal(value) && isscalar(value), ...
            'sixgr:truth:InvalidNoiseReference','Noise-ledger values must be scalar real numbers.');
        record.(field)=double(value);
    end
    for field=textFields
        value=string(r.(field));
        assert(isscalar(value) && ~ismissing(value) && strlength(strtrim(value))>0, ...
            'sixgr:truth:InvalidNoiseReference','Keep the executed noise source and domain.');
        record.(field)=value;
    end
    if record.NoiseOperatingMode=="absolute_reference_esn0"
        names=["AbsoluteReferenceNoise","SampleRate_Hz","PowerContextDirection", ...
            "AbsoluteReferenceNoiseInjectedSampleVariance_mW","AbsoluteReferenceNoiseInjectionDomain", ...
            "PowerContextAmplitudeUnit","RequestedReferenceEsN0_dB", ...
            "ReferenceNoisePSD_mWPerHz","ReferenceNoiseSampleVariance_mW", ...
            "ReferenceNoiseSampleRate_Hz","ReferenceNoiseContractSHA256", ...
            "ReferenceNoiseSource","ReferenceNoiseReferencePlane", ...
            "ThermalNoiseApplied","ControlledReferenceNoiseApplied"];
        assert(all(isfield(r,names)),'sixgr:truth:IncompleteNoiseReference', ...
            'Keep the original absolute-reference receipt and execution bindings.');
        for field=names, record.(field)=r.(field); end
    end
    localValidate(record);
    records{k}=record;
end
if ~any(present), return; end
assert(all(present),'sixgr:truth:IncompleteNoiseReference', ...
    'Every execution interval must retain the selected receiver''s noise ledger.');
assert(all(intervals(:,2)>intervals(:,1)) && ...
    intervals(1,1)<=observation.StartSample && intervals(end,2)>=observation.EndSampleExclusive && ...
    all(intervals(2:end,1)==intervals(1:end-1,2)), ...
    'sixgr:truth:NoiseReferenceCoverageGap','Noise evidence must cover the actual capture without gaps or overlap.');
r=records{1};
assert(all(cellfun(@(v)isequaln(v,r),records)), ...
    'sixgr:truth:NoiseReferenceChangedWithinCapture', ...
    'Do not flatten multiple noise calibrations or random-stream identities into one trial.');
if r.NoiseOperatingMode=="standalone_awgn_snr_argument" && ...
        ismember('ConfiguredSNR_dB',T.Properties.VariableNames)
    configured=double(T.ConfiguredSNR_dB);
    assert(all(isfinite(configured) & abs(configured-r.AppliedAWGNSNR_dB)<=1e-10), ...
        'sixgr:truth:FixedAWGNOperatingPointMismatch', ...
        'Configured trial labels must match the physically executed noise reference.');
end
if r.NoiseOperatingMode=="absolute_reference_esn0"
    publication=sixgr.link.absoluteReferenceNoisePublication(r);
    for field=string(fieldnames(publication)).'
        T.(field)=repmat(publication.(field),height(T),1);
    end
end
% These are injection/reference quantities. Never overwrite NoiseVariance,
% SNRReferencePlane, SINR, RSRP, or the practical receiver's estimator source.
for field=setdiff(fields,["InjectedNoiseVariance","InjectedNoiseVarianceDomain", ...
        "NoiseVarianceSource","WaveformAmplitudeUnit"])
    T.(field)=repmat(r.(field),height(T),1);
end
T.InjectedSampleNoiseVariance=repmat(r.InjectedNoiseVariance,height(T),1);
T.InjectedSampleNoiseVarianceDomain=repmat(r.InjectedNoiseVarianceDomain,height(T),1);
T.InjectedSampleNoiseVarianceSource=repmat(r.NoiseVarianceSource,height(T),1);
T.NoiseReferenceWaveformAmplitudeUnit=repmat(r.WaveformAmplitudeUnit,height(T),1);
T.NoiseReferenceReceiverID=repmat(receiver,height(T),1);
T.NoiseReferenceStartSample=repmat(observation.StartSample,height(T),1);
T.NoiseReferenceEndSampleExclusive=repmat(observation.EndSampleExclusive,height(T),1);
T.NoiseReferenceEvidenceSource=repmat("same_execution_receiver_noise_ledger_post_decode_export",height(T),1);
gridPlane="not_applicable_thermal_sample_noise";
if r.NoiseOperatingMode=="standalone_awgn_snr_argument"
    gridPlane="configured_NR_carrier_OFDM_occupied_RE_not_PRACH_demodulator_or_post_equalization";
elseif r.NoiseOperatingMode=="absolute_reference_esn0"
    gridPlane="not_applicable_absolute_reference_PSD_times_actual_sample_rate";
end
T.NoiseReferenceGridPlane=repmat(gridPlane,height(T),1);
end

function localValidate(r)
assert(isfinite(r.InjectedNoiseVariance) && r.InjectedNoiseVariance>0 && ...
    isfinite(r.NoiseStreamSeed) && r.NoiseStreamSeed>=0 && r.NoiseStreamSeed==fix(r.NoiseStreamSeed) && ...
    r.InjectedNoiseVarianceDomain=="receiver_sample_waveform_pre_composite_front_end", ...
    'sixgr:truth:InvalidNoiseReference','Keep the executed pre-front-end sample variance and stream identity.');
if r.NoiseOperatingMode=="standalone_awgn_snr_argument"
    values=[r.SignalEnergyPerOccupiedRE r.ReferenceAWGNGridNoiseVariance ...
        r.ReferenceAWGNSampleNoiseVariance r.SampleToGridNoiseVarianceGain];
    assert(all(isfinite(values) & values>0) && isfinite(r.RequestedAWGNReferenceSNR_dB) && ...
        isfinite(r.AppliedAWGNSNR_dB), ...
        'sixgr:truth:SharedFixedSNRNoiseClosure','Fixed-SNR calibration operands must be available.');
    expected=r.SignalEnergyPerOccupiedRE*10^(-r.RequestedAWGNReferenceSNR_dB/10);
    assert(abs(r.ReferenceAWGNGridNoiseVariance-expected)<=1e-12*expected && ...
        abs(r.InjectedNoiseVariance-r.ReferenceAWGNSampleNoiseVariance)<=1e-12*r.InjectedNoiseVariance && ...
        abs(r.InjectedNoiseVariance*r.SampleToGridNoiseVarianceGain-expected)<=1e-12*expected && ...
        abs(r.AppliedAWGNSNR_dB-10*log10(r.SignalEnergyPerOccupiedRE/ ...
        (r.InjectedNoiseVariance*r.SampleToGridNoiseVarianceGain)))<=1e-10, ...
        'sixgr:truth:SharedFixedSNRNoiseClosure', ...
        'Close occupied-RE energy through the OFDM transform to the variance actually injected.');
elseif r.NoiseOperatingMode=="absolute_reference_esn0"
    expected=sixgr.link.resolveAbsoluteReferenceNoiseVariance(r);
    assert(isequal(r.ThermalNoiseApplied,false)&&isequal(r.ControlledReferenceNoiseApplied,true)&& ...
        isnan(r.ThermalSampleNoiseBandwidth_Hz)&&isnan(r.ThermalNoisePSD_mWPerHz)&& ...
        isnan(r.AppliedAWGNSNR_dB)&&abs(r.InjectedNoiseVariance-expected)<=1e-12*expected, ...
        'sixgr:truth:SharedAbsoluteReferenceNoiseClosure', ...
        'Nominal absolute reference noise must not acquire thermal or measured-SINR labels.');
elseif r.NoiseOperatingMode=="receiver_noise_figure_thermal_noise"
    expected=r.ThermalSampleNoiseBandwidth_Hz*r.ThermalNoisePSD_mWPerHz;
    assert(isfinite(expected) && r.ThermalSampleNoiseBandwidth_Hz>0 && r.ThermalNoisePSD_mWPerHz>0 && ...
        abs(r.InjectedNoiseVariance-expected)<=1e-10*r.InjectedNoiseVariance && ...
        r.WaveformAmplitudeUnit=="sqrt_mW" && ...
        all(isnan([r.RequestedAWGNReferenceSNR_dB r.SignalEnergyPerOccupiedRE ...
        r.ReferenceAWGNGridNoiseVariance r.ReferenceAWGNSampleNoiseVariance ...
        r.SampleToGridNoiseVarianceGain r.AppliedAWGNSNR_dB])), ...
        'sixgr:truth:SharedThermalNoiseClosure', ...
        'Thermal noise must close from PSD and sample bandwidth, not an AWGN label.');
else
    error('sixgr:truth:SharedNoiseOperatingModeUnsupported', ...
        'Unrecognized executed noise mode %s.',r.NoiseOperatingMode);
end
end
