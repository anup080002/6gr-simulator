function newer=preserveServingGeometry(earlier,newer)
% A delayed decoded trial enriches an existing row, not its past geometry.
names=["Lat","Lon","X_m","Y_m","Z_m","Speed_kmh","Speed_mps", ...
    "Heading_deg","Heading_rad","CellID","ServingCell","ServingSite", ...
    "ServingSector","ServingBeamIndex","ServingBeamGain_dB", ...
    "BasePathloss_dB","Pathloss_dB","LOSFlag","LOSState","ShadowFading_dB", ...
    "O2I_dB","Distance2D_m","Distance3D_m","PropagationDelay_s", ...
    "RadialVelocity_mps","ExpectedDopplerHz","AppliedDopplerHz","SignedDoppler_Hz", ...
    "ProjectedRadialDopplerHz","DopplerQuantity","DopplerSourceMode","AppliedDopplerSource", ...
    "PositionValidAtTime_s","PositionValidAtSample","PositionSnapshotAtSample", ...
    "PositionSampleRateHz","MobilityStateVersion","PositionSource","VelocityReferenceFrame", ...
    "ModelPredictedRxPower_dBm","ModelPredictedRxPowerSource", ...
    "RxPower_dBm","RxPowerSource","RxPowerValueRole","PowerEvidenceContractVersion"];
assert(earlier.Slot==newer.Slot && earlier.UEID==newer.UEID, ...
    'sixgr:truth:ServingGeometryIdentityMismatch','Cannot merge different UE/slot geometry.');
for name=names
    if ismember(name,string(earlier.Properties.VariableNames)), newer.(name)=earlier.(name); end
end
end
