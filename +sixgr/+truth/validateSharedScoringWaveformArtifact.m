function verified=validateSharedScoringWaveformArtifact(root,manifest,row,evidence,waveform)
%VALIDATESHAREDSCORINGWAVEFORMARTIFACT Verify persisted effective-link IQ.
% Expected operands must come from the completed same-execution observation,
% not from the archive being validated. No receiver, channel or RF execution
% occurs here. The desired-link scoring plane is NOT the practical RX input.
% This read-only function never repairs, overwrites or completes an archive.
arguments
    root (1,1) string
    manifest (1,1) struct
    row table
    evidence (1,1) struct
    waveform {mustBeNumeric,mustBeFinite,mustBeNonempty}
end
invalid='sixgr:truth:InvalidSharedScoringArtifact';
partial='sixgr:truth:IncompleteSharedScoringArtifacts';
try
    assert(isfolder(root) && height(row)==1 && ...
        ismatrix(waveform) && isfloat(waveform) && ~issparse(waveform), ...
        invalid,'An existing run root, one observation and exact floating-point IQ are required.');
    required={'Contract','Representation','Source','Scope','LinkID', ...
        'TransmitterID','ReceiverID','SampleRateHz','StartSample', ...
        'EndSampleExclusive','WaveformSHA256','ReceiverEstimatorInput', ...
        'AdditionalChannelExecutions','AdditionalRFExecutions'};
    assert(all(isfield(manifest,required)) && ...
        string(manifest.Contract)=="actual_shared_effective_link_waveform/v1" && ...
        string(manifest.Representation)== ...
        "complete_sample_indexed_desired_link_IQ_not_path_gain_tensor" && ...
        string(manifest.Source)=="actual_executed_link_contribution" && ...
        string(manifest.Scope)== ...
        "effective_pilot_response_includes_actual_tx_rf_not_isolated_pure_channel_matrix", ...
        invalid,'Only the complete same-execution desired-link IQ contract is accepted.');
    assert(isequal(manifest.ReceiverEstimatorInput,false) && ...
        isequal(manifest.AdditionalChannelExecutions,0) && ...
        isequal(manifest.AdditionalRFExecutions,0) && ...
        isfield(evidence,'ReceiverEstimatorInput') && ...
        isequal(evidence.ReceiverEstimatorInput,false) && ...
        isfield(evidence,'AdditionalChannelExecutions') && ...
        isequal(evidence.AdditionalChannelExecutions,0) && ...
        isfield(evidence,'AdditionalRFExecutions') && ...
        isequal(evidence.AdditionalRFExecutions,0), ...
        invalid,'Do not validate a receiver-input, regenerated or proxy scoring plane as executed IQ.');
    for name=["Source","Scope","LinkID","TransmitterID","ReceiverID"]
        assert(isfield(evidence,name) && ...
            isscalar(string(manifest.(name))) && ...
            ~ismissing(string(manifest.(name))) && ...
            strlength(string(manifest.(name)))>0 && ...
            isequal(string(manifest.(name)),string(evidence.(name))), ...
            invalid,'The expected manifest must bind the executed %s.',name);
    end
    first=double(manifest.StartSample); stop=double(manifest.EndSampleExclusive);
    fs=double(manifest.SampleRateHz);
    assert(isscalar(first) && isscalar(stop) && isscalar(fs) && ...
        all(isfinite([first stop fs])) && first>=0 && stop>first && ...
        all([first stop]==fix([first stop])) && fs>0 && ...
        size(waveform,1)==stop-first && ...
        isfield(evidence,'StartSample') && isfield(evidence,'EndSampleExclusive') && ...
        isequal(double(evidence.StartSample),first) && ...
        isequal(double(evidence.EndSampleExclusive),stop), ...
        invalid,'IQ dimensions and evidence clocks must cover the exact observation.');
    waveformHash=string(manifest.WaveformSHA256);
    assert(isscalar(waveformHash) && ~ismissing(waveformHash) && ...
        ~isempty(regexp(char(waveformHash),'^[a-f0-9]{64}$','once')), ...
        invalid,'The expected observation must bind its complete runtime-array hash.');
    id="effch_"+sixgr.phy.waveform.WaveformHash.bytes( ...
        string(manifest.LinkID)+"|"+string(first)+"|"+string(stop)+"|"+waveformHash);
    matRelative=fullfile('channel','mat',id+".mat");
    csvRelative=fullfile('channel','csv',id+"_segments.csv");
    expected=table(id,string(manifest.LinkID),string(manifest.TransmitterID), ...
        string(manifest.ReceiverID),first,stop,fs,size(waveform,1), ...
        size(waveform,2),waveformHash,string(matRelative),false,0,0, ...
        'VariableNames',{'ChannelObservationID','LinkID','TransmitterID', ...
        'ReceiverID','StartSample','EndSampleExclusive','SampleRateHz', ...
        'TimeSampleCount','ReceiveBranchCount','WaveformSHA256','WaveformMATFile', ...
        'ReceiverEstimatorInput','AdditionalChannelExecutions','AdditionalRFExecutions'});
    localCheckRow(row,expected,invalid);
    matPath=fullfile(root,matRelative); csvPath=fullfile(root,csvRelative);
    assert(isfile(matPath) && isfile(csvPath),partial, ...
        'The immutable scoring observation requires both MAT and CSV artifacts.');
    matHash=sixgr.phy.waveform.WaveformHash.file(matPath);
    csvHash=sixgr.phy.waveform.WaveformHash.file(csvPath);
    types=struct();
    for name=string(expected.Properties.VariableNames)
        if isstring(expected.(name)), types.(name)="string";
        else, types.(name)="double";
        end
    end
    savedRow=sixgr.util.csvReadTable(csvPath,'ColumnTypes',types);
    localCheckRow(savedRow,expected,invalid);
    [arrayEvidence,fileEvidence]=sixgr.util.withVerifiedMAT(matPath,matHash,@readPayload);
    assert(sixgr.phy.waveform.WaveformHash.file(csvPath)==csvHash,invalid, ...
        'The CSV changed while the complete MAT/CSV observation was verified.');
    verified=struct('ChannelObservationID',id,'Manifest',manifest, ...
        'MATFile',string(matRelative),'MATFileSHA256',matHash, ...
        'SegmentsCSV',string(csvRelative),'SegmentsCSVSHA256',csvHash, ...
        'WaveformSHA256',waveformHash,'ArrayReadEvidence',arrayEvidence, ...
        'MATReadEvidence',fileEvidence,'ExpectedValuesCompared',true, ...
        'ReceiverEstimatorInput',false,'AdditionalChannelExecutions',0, ...
        'AdditionalRFExecutions',0);
catch cause
    if any(string(cause.identifier)==[string(invalid),string(partial)])
        rethrow(cause);
    end
    failure=MException(invalid,'Cannot verify the immutable effective-link IQ artifact.');
    failure=addCause(failure,cause);
    throwAsCaller(failure);
end

    function details=readPayload(path)
        metadata=load(path,'ManifestJSON','Evidence');
        assert(all(isfield(metadata,{'ManifestJSON','Evidence'})) && ...
            isequal(string(metadata.ManifestJSON),string(jsonencode(manifest))) && ...
            isequaln(metadata.Evidence,evidence),invalid, ...
            'Saved manifest and execution evidence must match the current executed observation.');
        if H5F.is_hdf5(path)>0
            archive=matfile(path);
            inventory=whos(archive,'DesiredLinkWaveform');
            assert(isscalar(inventory) && ...
                string(inventory.class)==string(class(waveform)) && ...
                isequal(size(archive,'DesiredLinkWaveform'),size(waveform)),invalid, ...
                'Stored IQ class and dimensions differ from the executed samples.');
            [digest,details]=sixgr.phy.waveform.runtimeArrayMATFileHash( ...
                archive,"DesiredLinkWaveform",1048576,@compareBlock);
        else
            % Legacy v7 archives cannot be partially loaded. Preserve exact
            % validation and disclose this allocation; never pretend that
            % MAT-file indexing makes a v7 read block-wise.
            data=load(path,'DesiredLinkWaveform');
            assert(isfield(data,'DesiredLinkWaveform') && ...
                strcmp(class(data.DesiredLinkWaveform),class(waveform)) && ...
                isequaln(data.DesiredLinkWaveform,waveform),invalid, ...
                'Stored IQ must equal every executed complex value, without fitting or rescaling.');
            digest=sixgr.phy.waveform.WaveformHash.runtimeArray(data.DesiredLinkWaveform);
            details=struct('Dimensions',size(waveform),'Class',string(class(waveform)), ...
                'ElementCount',numel(waveform),'AllFinite',true, ...
                'FullArrayLoaded',true,'SourceFormat',"legacy_MAT_full_variable_read");
        end
        assert(string(digest)==waveformHash && details.AllFinite,invalid, ...
            'Actual archived IQ does not match the observation waveform hash.');
    end

    function compareBlock(block,indices)
        assert(strcmp(class(block),class(waveform)) && ...
            isequaln(block,waveform(indices{:})),invalid, ...
            'An archived complex sample differs from its same-execution observation.');
    end
end

function localCheckRow(actual,expected,identifier)
assert(height(actual)==1 && ...
    isequal(string(actual.Properties.VariableNames),string(expected.Properties.VariableNames)), ...
    identifier,'The scoring CSV must contain the exact one-observation schema and row.');
for name=string(expected.Properties.VariableNames)
    a=actual.(name); b=expected.(name);
    if name=="WaveformMATFile"
        % Separators may differ when the immutable run moves between hosts.
        same=isequal(replace(string(a),'\','/'),replace(string(b),'\','/'));
    elseif isstring(b)
        same=isequal(string(a),b);
    else
        same=(isnumeric(a)||islogical(a)) && isequal(double(a),double(b));
    end
    assert(same,identifier,'Scoring CSV field %s differs from the executed observation.',name);
end
end
