function state=installSharedReceivedPUCCHPower(state,cfg,ue)
% Explicit configured P0 activation at first connected control preparation.
% A received C-RNTI authorizes identity, NOT decoded RRC P0 content.
p=sixgr.util.structGet(cfg,'validation.pucch_resources.power_control',struct());
p=sixgr.phy.pucch.validateReceivedPowerPolicy(p);
mode=string(sixgr.util.structGet(p,'closed_loop_mode','configured'));
assert(any(mode==["configured","received_dci"]),'sixgr:truth:PUCCHPowerPolicy','Unknown power owner policy.');
if mode=="configured", return; end
id='sixgr:truth:PUCCHPowerInstallation';
assert(string(p.received_dci_installation_policy)== ...
    "configured_dedicated_p0_at_first_connected_control_preparation" && ...
    isfield(state,'SharedWaveformStream') && ...
    sixgr.truth.CoupledRadioIdentity.connectedReady(state,ue),id, ...
    'Install only an explicit configured P0 policy after connected identity is available.');
stream=state.SharedWaveformStream;
cellID=double(cfg.lls6g.userContext.RuntimeServingCell);
rnti=sixgr.truth.CoupledRadioIdentity.resolve(state,ue,cellID);
assert(cfg.phy.pdsch.RNTI==rnti && cfg.lls6g.userContext.UEIndex==ue && ...
    ~sixgr.rf.isNormalizedFixedSNRPowerReference(cfg),id, ...
    'Original connected UE and absolute power authority are required.');
radio=sixgr.util.structGet(state,'RadioIdentityBindings',struct([]));
binding=struct();
if logical(sixgr.util.structGet(state,'ControlGating.PRACHRequired',false))
    assert(~isempty(radio),id,'The received C-RNTI installation must exist before connected power activation.');
    hit=[radio.UEIndex]==ue & [radio.ServingCell]==cellID & [radio.RNTI]==rnti;
    assert(nnz(hit)==1,id,'A bootstrap RNTI cannot own received connected PUCCH g.');
    binding=radio(hit);
    assert(binding.Source=="decoded_msg4_payload_after_contention_match" && ...
        ~binding.MACRRCStandardsQualified,id,'Retain the actual bounded received identity provenance.');
    identitySource="received_connected_identity_activates_configured_P0_not_decoded_RRC_P0";
else
    identitySource="explicit_preconnected_configured_identity_and_P0";
end
owners=sixgr.util.structGet(state,'SharedReceivedPUCCHPowerOwners',{});
proofs=sixgr.util.structGet(state,'SharedReceivedPUCCHPowerInstallations',{});
c=sixgr.phy.grid.makeCarrier(cfg);
assert(string(c.CyclicPrefix)=="normal",id,'Only the supported normal-CP symbol domain is installed.');
context=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,'1_1');
assert(context.Data.RNTIValue==rnti && context.Data.RNTIType=="C-RNTI" && ...
    context.Data.ControlServingCell==context.Data.ScheduledServingCell && ...
    context.Data.ControlCarrier==context.Data.ScheduledCarrier,id, ...
    'Configured DCI indices must explicitly bind this same-serving-carrier receiver.');
spatial=cfg.validation.pucch_resources.spatial_relations;
hit=[spatial.id]==[spatial.active_id];
assert(nnz(hit)==1,id,'Require one active installed spatial P0/loop identity.');
s=spatial(hit);
autonomous=string(p.received_dci_autonomous_policy);
[k2,commonTiming]=sixgr.truth.resolvePUCCHCommonK2(state,cfg,ue,p,context);
ueIdentity=cfg.phy.frame.DefaultIdentity;
if numel(owners)>=ue && ~isempty(owners{ue})
    b=owners{ue}.Installation;
    assert(numel(proofs)>=ue && b.RNTI==rnti && b.ServingCell==cellID && b.P0_dBm==p.p0_dbm && ...
        b.ClockEpoch==stream.Physical.ConfigurationEpoch && b.SampleRateHz==stream.SampleRateHz && ...
        b.SubcarrierSpacingKHz==double(c.SubcarrierSpacing) && b.ActiveULBWP==ueIdentity.ULBWPID && ...
        b.ComponentCarrier==ueIdentity.ScheduledCCID && b.P0PUCCHID==s.p0_pucch_id && ...
        b.ClosedLoopIndex==s.closed_loop_index && b.DCIServingCellIndex==context.Data.ControlServingCell && ...
        b.DCIComponentCarrierIndex==context.Data.ControlCarrier && isequal(b.CommonK2Slots,k2) && ...
        string(proofs{ue}.ConfiguredPower.received_dci_autonomous_policy)==autonomous && ...
        string(proofs{ue}.CommonTimingAuthority.Source)==string(commonTiming.Source) && ...
        isequaln(proofs{ue}.RadioIdentityBinding,binding),id, ...
        'Do not retag/reset an existing owner on an identity, P0/loop/BWP, common-K2 or clock reconfiguration.');
    return; % Repeated delivery of semantically identical common values is idempotent.
end
now=double(stream.Events.NextSampleIndex);
slot0=double(state.CurrentSlot)-1;
c.NSlot=mod(slot0,double(c.SlotsPerFrame));
info=nrOFDMInfo(c,'SampleRate',stream.SampleRateHz,'Windowing',0);
offset=mod(slot0,double(c.SlotsPerSubframe))*14;
edges=sixgr.phy.frame.slotStartSample(c,slot0,stream.SampleRateHz)+ ...
    [0 cumsum(double(info.SymbolLengths(offset+(1:14))))];
next=find(edges>=now,1);
assert(~isempty(next),id,'Installation must retain its current actual sample boundary.');
e=struct('ContractVersion',"sixgr.truth.shared_received_PUCCH_installation/v1", ...
    'UEIndex',ue,'RNTI',rnti,'ServingCell',cellID,'ConfiguredPower',p, ...
    'RadioIdentityBinding',binding,'IdentitySource',identitySource,'CommonTimingAuthority',commonTiming, ...
    'AvailableAtSample',now,'EffectiveSample',now,'FirstEligibleSymbolBoundary',14*slot0+next-1, ...
    'SampleRateHz',stream.SampleRateHz,'ClockEpoch',stream.Physical.ConfigurationEpoch, ...
    'DecodedRRCP0',false,'MACRRCStandardsQualified',false);
e.SHA256=string(sixgr.util.sha256Hex(char(jsonencode(e))));
b=struct('InstallationID',"PUCCH-P0-"+e.SHA256,'UEID',double(ue),'RNTI',double(rnti), ...
    'ServingCell',cellID,'ComponentCarrier',double(ueIdentity.ScheduledCCID), ...
    'ActiveULBWP',double(ueIdentity.ULBWPID),'DCIServingCellIndex',double(context.Data.ControlServingCell), ...
    'DCIComponentCarrierIndex',double(context.Data.ControlCarrier),'ClosedLoopIndex',double(s.closed_loop_index), ...
    'P0PUCCHID',double(s.p0_pucch_id),'P0_dBm',p.p0_dbm,'EffectiveSample',now, ...
    'EffectiveSymbolBoundary',double(e.FirstEligibleSymbolBoundary),'AvailableAtSample',now, ...
    'SampleRateHz',stream.SampleRateHz,'ClockEpoch',double(stream.Physical.ConfigurationEpoch), ...
    'SubcarrierSpacingKHz',double(c.SubcarrierSpacing),'CyclicPrefix',string(c.CyclicPrefix), ...
    'CommonK2Slots',k2,'ProcessingCapability',"capability1", ...
    'Source',"installed_dedicated_p0_configuration",'AutonomousOccasionsSupported',autonomous~="response_only");
owners{ue}=sixgr.link.ReceivedPUCCHPowerControlState(b); proofs{ue}=e;
state.SharedReceivedPUCCHPowerOwners=owners;
state.SharedReceivedPUCCHPowerInstallations=proofs;
end
