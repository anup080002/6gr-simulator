function requirePostAttachWindow(numSlots,blockedSlotCount)
% A data-plane truth campaign cannot qualify an entirely access-gated run.
validateattributes(numSlots,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(blockedSlotCount,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
if blockedSlotCount>=numSlots
    error('sixgr:e2e:InsufficientPostAttachWindow', ...
        ['Received access blocks %d slots, but the requested campaign contains only %d. ' ...
        'No connected data can execute. Explicitly configure a longer duration and slot ' ...
        'limit, allowing data scheduling and feedback after access completion. ' ...
        'An empty grant stream is not a successful data-plane validation.'], ...
        blockedSlotCount,numSlots);
end
end
