function prepared=prepareCellRARTransmission(cfg,ra,plan)
% Prepare a cell-owned common RAR; only the shared owner executes TX RF.
assert(ra.ContractVersion=="cell_received_RAR_transmission_context/v1" && ...
    ra.ContextSHA256==localHash(rmfield(ra,'ContextSHA256')) && ra.ResponseSchedulable && ...
    plan.ContractVersion=="cell_received_rar_plan/v1" && plan.ResponseRequired && ...
    plan.PlanSHA256==localHash(rmfield(plan,'PlanSHA256')) && ...
    plan.OriginalCellContext.ServingCell==ra.ServingCell && ...
    plan.OriginalCellContext.RARNTI==ra.RARNTI && ...
    plan.OriginalCellContext.PRACHAbsoluteSlot==ra.PRACHAbsoluteSlot, ...
    'sixgr:truth:CellRARPreparationContract','Retain one original schedulable cell response and allocation transaction.');
[tx,schedule]=sixgr.phy.ra.generateMsg2RARWaveform(cfg,ra,plan.RAR);
assert(size(tx.Waveform,2)==1,'sixgr:truth:CellRARLogicalPortMismatch','Common RAR has one logical layer/port before its SSB mapping.');
info=nrOFDMInfo(tx.Carrier); fs=info.SampleRate;
first=sixgr.phy.frame.slotStartSample(tx.Carrier,ra.Msg2Slot,fs);
assert(first>=ra.ReceiverCompletedAtSample,'sixgr:truth:CellRARCausalPreparation','Do not enqueue a RAR before its actual received detection.');
cfg.lls6g.userContext.RuntimeSignalFamily="Msg2";
cfg.lls6g.userContext.RuntimeCurrentDirection="DL";
cfg.lls6g.userContext.Direction="DL";
cfg.lls6g.userContext.RuntimeServingCell=ra.ServingCell;
cfg.lls6g.userContext.RuntimeServingCellIndex=ra.ServingCell;
source="lls6g.resolvedConfig.power_and_rf_frontend.bs_tx_power_dbm";
power=sixgr.util.structGet(cfg,source,NaN);
if sixgr.rf.isNormalizedFixedSNRPowerReference(cfg)
    power=0; source="normalized_fixed_esn0_unit_occupied_re_es";
else
    validateattributes(power,{'numeric'},{'scalar','real','finite'});
end
ctx=sixgr.rf.PowerContext(cfg,'DL','NumPorts',1);
ctx.TotalTxPower_dBm=power; ctx.TotalTxPower_mW=10^(power/10);
ctx.TotalTxPower_W=ctx.TotalTxPower_mW*1e-3; ctx.TotalTxPowerSource=char(source);
ctx.SignalSpecificPowerControl=true; ctx.SignalFamily='Msg2';
txInfo=struct('OFDM',info,'PortGrid',tx.Grid, ...
    'PowerNormalizationGridSource',"exact_cell_RAR_composite_pdcch_pdsch_grid");
[wave,ctx]=sixgr.rf.applyPowerContext(tx.Waveform,cfg,'DL',txInfo,'PowerContext',ctx,'ApplyPA',false);
selected=sixgr.phy.ia.SSBBurstPlan.selectedPrecoderFromConfig(cfg,ra.AssociatedSSBIndex0);
[matrix,beam,association]=sixgr.phy.ra.resolveAssociatedSSBProjection(cfg,selected.NumTransmitAntennas);
physical=wave*cast(matrix,'like',wave).';
% RNTI is immaterial to this rectangular resource projection; retain a real
% allocated temporary identity rather than the scenario's intended identity.
reservationContext=ra; reservationContext.TempCRNTI=plan.Assignments(1).TemporaryCRNTI;
reservations=sixgr.truth.CommonRAResourceCalendar.fromTransmission(tx,reservationContext,"Msg2");
tx.PowerControl=struct('Msg2TxPower_dBm',power,'DownlinkTxPowerSource',source, ...
    'Scope',"configured_cell_power_budget_before_shared_TX_RF");
unit=sixgr.rf.appliedWaveformAmplitudeUnit(cfg,ctx);
prepared=struct('ContractVersion',"prepared_cell_RAR/v1",'StageName',"Msg2",'Direction',"DL", ...
    'AbsoluteSlot',ra.Msg2Slot,'ServingCell',ra.ServingCell,'RARNTI',ra.RARNTI, ...
    'Waveform',tx.Waveform,'PhysicalWaveform',physical, ...
    'SampleRate_Hz',fs,'SampleCount',size(physical,1),'PortCount',1, ...
    'PhysicalPortCount',size(physical,2),'Duration_s',size(physical,1)/fs, ...
    'StartTime_s',first/fs,'EndTimeExclusive_s',(first+size(physical,1))/fs, ...
    'TransmitStartSample',first,'TimeReference',"absolute_cell_sample_clock", ...
    'ExecutionStatus',"generated_not_propagated",'RFExecutionDeferred',true, ...
    'PowerContext',ctx,'CommonResourceReservations',reservations, ...
    'TransmitMappingSource',"original_cell_RO_CB_preamble_partition_SSB_precoder", ...
    'TransmitBeamID',beam,'TransmitProjectionMatrix',matrix, ...
    'TransmitProjectionMatrixSHA256',string(sixgr.phy.mimo.MatrixContract.digest(matrix)), ...
    'TxSSBAssociationJSON',string(jsonencode(association)), ...
    'PhysicalWaveformPlane',"physical_antenna_"+unit+"_before_shared_tx_rf", ...
    'ReceiverReceiptSHA256',ra.ReceiverReceiptSHA256,'CellCalendarSHA256',ra.CellCalendarSHA256, ...
    'RARPlan',plan,'RAContext',ra,'Tx',tx,'Schedule',schedule,'Config',cfg);
end
function h=localHash(value)
h=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(value))));
end
