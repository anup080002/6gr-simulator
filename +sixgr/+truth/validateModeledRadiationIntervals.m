function complete=validateModeledRadiationIntervals(T,library,intervals,spatial,native)
% Recompute only retained model arithmetic, never RF/PHY or installed config.
id='sixgr:truth:ModeledRadiationClosure'; complete=false;
assert(isstruct(library)&&all(isfield(library,{'Installation','Field'})),id,'Require immutable field library.');
ids=strings(numel(library),1); endpoints=ids;
for k=1:numel(library)
    a=library(k).Installation; f=library(k).Field;
    sixgr.rf.InstalledTXRadiationBinding.validateArchivedField(a,f);
    ids(k)=a.InstallationSHA256; endpoints(k)=a.TransmitterID;
end
assert(numel(unique(ids))==numel(ids)&&numel(unique(endpoints))==numel(endpoints),id, ...
    'Exactly one immutable installation per registered transmitter.');
prototype=sixgr.truth.modeledRadiationInterval();
assert(istable(T)&&all(ismember(prototype.Properties.VariableNames,T.Properties.VariableNames)),id,'Missing radiation columns.');
assert(isstruct(native)&&all(isfield(native,{'LinkID','Receipt'})),id,'Require original native installation journal.');
nativeHashes=strings(numel(native),1);
for k=1:numel(native)
    r=native(k).Receipt; nativeHashes(k)=string(r.ReceiptSHA256);
    n=find(ids==string(r.InstallationSHA256));
    assert(isscalar(n)&&strlength(string(native(k).LinkID))>0&& ...
        nativeHashes(k)==sha(rmfield(r,'ReceiptSHA256'))&& ...
        string(r.Contract)=="sixgr.native_TX_radiation_installation/v1"&& ...
        string(r.NativeGetter)=="current_TransmitAntennaArray_no_second_swap"&& ...
        isscalar(string(r.StateKey))&&strlength(string(r.StateKey))>0&& ...
        string(r.Source)=="actual_materialized_native_channel_installation"&& ...
        ~r.WaveformExecutionVerified&&~r.HardwareConformanceVerified,id,'Invalid original native installation receipt.');
    a=library(n).Installation;
    assert(string(r.TransmitterID)==string(a.TransmitterID)&&string(r.Direction)==string(a.Direction)&& ...
        r.SampleRateHz==a.SampleRateHz&&r.PhysicalConfigurationEpoch==a.PhysicalConfigurationEpoch&& ...
        r.CarrierFrequencyHz==a.Geometry.CarrierFrequencyHz&& ...
        string(r.NativeDefinitionSHA256)==string(a.Geometry.NativeDefinitionSHA256)&& ...
        isequal(r.NativeArrayOrientation_deg,a.Geometry.NativeArrayOrientation_deg)&& ...
        isfinite(r.AtSample)&&r.AtSample>=a.RFStreamOriginSample&&r.AtSample==fix(r.AtSample),id, ...
        'Native array binding cannot be transplanted to another endpoint, field or clock.');
end
assert(numel(unique(nativeHashes))==numel(nativeHashes),id,'Duplicate native installation receipts.');
assert(numel(unique(string(T.EndpointID)+"|"+string(T.StartSample)))==height(T),id,'Duplicate model intervals.');
for k=1:height(T)
    row=T(k,:); n=find(ids==row.InstallationSHA256);
    assert(isscalar(n),id,'Unknown immutable installation.'); a=library(n).Installation;
    base=intervals(intervals.Role=="TX"&intervals.EndpointID==row.EndpointID&intervals.StartSample==row.StartSample,:);
    p=spatial(spatial.EndpointID==row.EndpointID&spatial.StartSample==row.StartSample,:);
    assert(height(base)==1&&height(p)==1&&row.EndpointID==string(a.TransmitterID)&& ...
        row.Direction==string(a.Direction)&&row.Direction==base.Direction&& ...
        row.EndSampleExclusive==base.EndSampleExclusive&&row.SampleCount==base.SampleCount&& ...
        row.SampleRateHz==base.SampleRateHz&&row.SampleRateHz==a.SampleRateHz&& ...
        row.ConfigurationEpoch==base.ConfigurationEpoch&&row.ConfigurationEpoch==a.PhysicalConfigurationEpoch&& ...
        row.PhysicalChainCount==base.PhysicalPortCount&&row.PhysicalChainCount==a.PhysicalChainCount&& ...
        row.RFInputWaveformSHA256==base.InputWaveformSHA256&&row.RFOutputWaveformSHA256==base.OutputWaveformSHA256&& ...
        row.SpatialMatrixSHA256==p.MatrixSHA256&&row.FieldSHA256==string(a.FieldIdentity.FieldSHA256),id, ...
        'Model interval must join the exact original RF and covariance receipt.');
    r=jsondecode(char(row.ReceiptJSON));
    assert(string(jsonencode(r))==row.ReceiptJSON&&string(r.ReceiptSHA256)==row.ReceiptSHA256&& ...
        sha(rmfield(r,'ReceiptSHA256'))==row.ReceiptSHA256&& ...
        string(r.Contract)=="sixgr.executed_TX_radiation_binding/v1"&& ...
        string(r.TransmitterID)==row.EndpointID&&string(r.Direction)==row.Direction&& ...
        r.StartSample==row.StartSample&&r.EndSampleExclusive==row.EndSampleExclusive&& ...
        r.SampleCount==row.SampleCount&&r.SampleRateHz==row.SampleRateHz&& ...
        r.PhysicalConfigurationEpoch==row.ConfigurationEpoch&&r.PhysicalChainCount==row.PhysicalChainCount&& ...
        string(r.WaveformAmplitudeUnit)=="sqrt_mW"&&r.OriginalRFIntervalVerified&& ...
        string(r.CoordinateFrame)=="installed_array_local_coordinates"&& ...
        string(r.FrequencyScope)=="frequency_flat_installed_carrier_field_model"&& ...
        string(r.ReferencePlane)=="configured_far_field_pattern_model_from_actual_post_TX_RF_covariance"&& ...
        string(r.Source)=="original_TX_RF_samples_independently_rechecked_component_binding"&& ...
        ~r.InternalSamplePowerIsAcceptedFeedPower&&~r.NativeChannelExecutionQualified&& ...
        ~r.ProductionOwnerIntegrationVerified&&~r.AcceptedFeedPowerQualified&& ...
        ~r.HardwareConformanceVerified&&~r.PowerRenormalizationApplied,id,'Original strict binding cannot be relabeled.');
    for name=["InstallationSHA256","FieldSHA256","RFInputWaveformSHA256","RFOutputWaveformSHA256", ...
            "SpatialMatrixSHA256","InternalMeanSquare_mW","ModelTRP_mW","SampledPeakModelEIRP_mW","ModelResultSHA256"]
        if isnumeric(row.(name)), equal=isequaln(r.(name),row.(name));
        else, equal=isequaln(string(r.(name)),string(row.(name))); end
        assert(equal,id,'Receipt field %s changed.',name);
    end
    matrix=sixgr.runtime.RawCSVArrayCodec.decode(p.SecondMomentArray);
    measured=struct('Contract',"physical_tx_spatial_power/v1",'SecondMoment',matrix, ...
        'MatrixSHA256',p.MatrixSHA256,'PhysicalChainCount',p.PhysicalChainCount, ...
        'SampleCount',p.SampleCount,'TotalMeanSquare',p.TotalMeanSquare, ...
        'Plane',"actual_TX_RF_output_before_antenna_channel");
    model=sixgr.rf.integrateRadiatedSpatialPower(measured,library(n).Field,p.WaveformAmplitudeUnit);
    assert(row.ModelResultSHA256==sha(model)&&row.InternalMeanSquare_mW==p.TotalMeanSquare&& ...
        row.ModelTRP_mW==model.ModelTRP_mW&&row.SampledPeakModelEIRP_mW==model.SampledPeakModelEIRP_mW,id, ...
        'Retained covariance and field must reproduce the original model without normalization.');
    hashes=string(jsondecode(char(row.NativeInstallationReceiptSHA256sJSON))); hashes=hashes(:);
    assert(numel(unique(hashes))==numel(hashes)&&row.NativeChannelInstallationMatched==~isempty(hashes),id,'Invalid native binding population.');
    for h=reshape(hashes,1,[])
        at=find(nativeHashes==h); assert(isscalar(at),id,'Missing native installation binding.');
        b=native(at).Receipt;
        assert(string(b.InstallationSHA256)==row.InstallationSHA256&&b.AtSample<=row.StartSample,id,'Future or different native binding.');
    end
    for name=["ModelIntegratedRadiationVerified","AcceptedFeedPowerQualified","HardwareConformanceVerified", ...
            "PowerRenormalizationApplied","CoordinateFrame","FrequencyScope","Source"]
        assert(isequaln(row.(name),scopeValue(name)),id,'Model scope cannot be promoted.');
    end
end
expected=intervals(intervals.Role=="TX"&ismember(intervals.EndpointID,endpoints),:);
complete=~isempty(library)&&~isempty(expected)&&height(T)==height(expected);
assert(height(T)==height(expected),id,'Enabled endpoints require every committed interval, including idle input.');
end

function value=scopeValue(name)
switch name
    case 'ModelIntegratedRadiationVerified', value=true;
    case {'AcceptedFeedPowerQualified','HardwareConformanceVerified','PowerRenormalizationApplied'}, value=false;
    case 'CoordinateFrame', value="installed_array_local_coordinates";
    case 'FrequencyScope', value="frequency_flat_installed_carrier_field_model";
    case 'Source', value="canonical_shared_TX_RF_owner_completed_interval";
end
end
function out=sha(value)
out=string(sixgr.util.sha256Hex(unicode2native(jsonencode(value),'UTF-8')));
end
