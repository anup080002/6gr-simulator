function identity=validateUnselectedPUCCHTransmission(state,selection,producer)
% Preparation alone is not a physical UE transmission. Require both the
% owner's actual sample event and its matching MAC transmit receipt.
assert(isstruct(producer) && isscalar(producer), ...
    'sixgr:truth:UnselectedPUCCHProducerRequired','Retain the producer context.');
identity=struct();
if isempty(fieldnames(producer))
    assert(strlength(selection.PUCCHTransmissionID)==0, ...
        'sixgr:truth:UnselectedPUCCHProducerRequired','A selected TX identity needs its actual producer.');
    return;
end
owner=state.SharedWaveformStream;
assert(isa(owner,'sixgr.truth.CoupledWaveformStream'), ...
    'sixgr:truth:SharedPUCCHTXOwnerRequired','Use the actual shared physical owner.');
identity=sixgr.truth.preparedPUCCHTransmissionIdentity( ...
    producer.Prepared,selection.UEIndex,selection.PUCCHObservationID);
assert(identity.TransmissionID==selection.PUCCHTransmissionID && ...
    identity.EndSampleExclusive<=owner.Events.NextSampleIndex, ...
    'sixgr:truth:UnselectedPUCCHTXIncomplete','Require this complete, physically executed UE waveform.');
records=owner.PUCCHTransmissions;
hit=find(arrayfun(@(r)r.Identity.TransmissionID==identity.TransmissionID,records));
ledger=sixgr.util.structGet(state,'SharedPUCCHTXLedger',{});
committed=find(cellfun(@(r)r.Identity.TransmissionID==identity.TransmissionID,ledger));
assert(isscalar(hit) && isscalar(committed) && ...
    isequaln(records(hit).Identity,identity) && isequaln(ledger{committed}.Identity,identity) && ...
    records(hit).CommittedAtSample==records(hit).FirstActiveSample+1 && ...
    records(hit).CommittedAtSample==ledger{committed}.CommittedAtSample && ...
    isequaln(records(hit).WaveformToElementMatrix,ledger{committed}.WaveformToElementMatrix), ...
    'sixgr:truth:UnselectedPUCCHTXNotExecuted','Require the matching owner and MAC sample receipts, not an intent.');
end
