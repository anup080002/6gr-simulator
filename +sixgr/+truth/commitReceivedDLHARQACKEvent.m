function [state,event]=commitReceivedDLHARQACKEvent(state,cfg,control,decision,after,availableAtSample)
% Retain the UE-owned feedback event at actual shared receiver completion.
% This ledger does not establish a UCI transmission or a gNB decode outcome.
owner=state.SharedWaveformStream;
assert(isa(owner,'sixgr.truth.CoupledWaveformStream') && ...
    isequal(availableAtSample,owner.Events.NextSampleIndex), ...
    'sixgr:truth:HARQEventSharedClockRequired', ...
    'Commit feedback knowledge only at the current shared sample boundary.');
controls=state.SharedReceivedGrantControls;
hit=find(cellfun(@(x)isequal(x.Key,control.Key),controls));
assert(isscalar(hit) && isequaln(controls{hit},control) && control.Allowed, ...
    'sixgr:truth:HARQEventReceivedControlRequired', ...
    'The exact accepted shared PDCCH record must already exist.');
a=control.ReceivedAssignment;
event=sixgr.link.receivedDLHARQACKEvent(cfg,a,decision,after);
validateattributes(control.AvailableAtSample,{'numeric'}, ...
    {'scalar','real','finite','integer','nonnegative'});
carrier=sixgr.phy.grid.makeCarrier(cfg);
assert(control.AvailableAtSample>=sixgr.phy.frame.slotStartSample( ...
    carrier,a.ControlAbsoluteSlot,owner.SampleRateHz) && ...
    availableAtSample>=control.AvailableAtSample && ...
    availableAtSample>=sixgr.phy.frame.slotStartSample( ...
    carrier,a.DataAbsoluteSlot,owner.SampleRateHz), ...
    'sixgr:truth:HARQEventClockSlotMismatch', ...
    'Received control and UE decision must precede feedback availability.');
ledger=sixgr.util.structGet(state,'SharedUEHARQACKEvents',{});
assert(~any(cellfun(@(r)r.Event.Data.UEId==event.Data.UEId && ...
    r.Event.Data.ReceivedAssignmentDigest==event.Data.ReceivedAssignmentDigest,ledger)), ...
    'sixgr:truth:DuplicateReceivedHARQEvent', ...
    'One consumed UE assignment must enter the feedback ledger exactly once.');
ledger{end+1,1}=struct('Event',event, ...
    'ControlAvailableAtSample',control.AvailableAtSample, ...
    'AvailableAtSample',availableAtSample,'SampleRateHz',owner.SampleRateHz, ...
    'Source',"received_dci_and_ue_harq_transition_at_shared_completion", ...
    'FeedbackTransmissionQualified',false);
state.SharedUEHARQACKEvents=ledger;
end
