function evidence=ssbNativeSampleIntervals(T,carrier)
% Executed SS/PBCH CP/useful intervals on the native SSB clock.
% PRB intersections are an engineering resource-load operand, not native
% RE counts, received power, propagation delay or RF filter-tail duration.
evidence=struct('ExecutedSampleIntervalsJSON',"",'ExecutedSampleIntervalSource',"", ...
    'ResourceGridPRBCount',NaN,'NativeAllocationID',"",'NativeGridSHA256',"");
if nargin==0 || isempty(T), return; end
required={'channel','grid_domain','evidence_scope','active_flag','allocation_id', ...
    'native_symbol_index_from_burst','native_subcarrier_start','native_subcarrier_count', ...
    'grid_subcarrier_spacing_hz','grid_subcarrier_count','grid_symbol_count', ...
    'observation_sample_rate_hz','cp_start_sample','useful_start_sample', ...
    'useful_end_sample_exclusive','broadcast_start_sample','broadcast_end_sample_exclusive', ...
    'frequency_first_hz','frequency_last_hz','transmit_grid_sha256','ssb_index0'};
assert(istable(T) && all(ismember(required,T.Properties.VariableNames)) && ...
    all(string(T.channel)=="SSB") && all(string(T.grid_domain)=="ssb_native_cp_ofdm") && ...
    all(string(T.evidence_scope)=="runtime_observed_tx_occupancy") && all(T.active_flag==1), ...
    'sixgr:truth:SSBIntervalAuthority','Require executed native SS/PBCH grid evidence.');
for name=["allocation_id","ssb_index0","transmit_grid_sha256","observation_sample_rate_hz", ...
        "broadcast_start_sample","broadcast_end_sample_exclusive","grid_subcarrier_spacing_hz", ...
        "grid_subcarrier_count","grid_symbol_count"]
    assert(numel(unique(T.(name)))==1,'sixgr:truth:SSBIntervalIdentity', ...
        'One transmitted SSB must have one %s.',name);
end
assert(~isempty(regexp(char(string(T.transmit_grid_sha256(1))),'^[a-f0-9]{64}$','once')), ...
    'sixgr:truth:SSBIntervalHash','Native SSB evidence requires its actual mapped-grid hash.');
fs=double(T.observation_sample_rate_hz(1)); scs=double(T.grid_subcarrier_spacing_hz(1));
origin=double(T.broadcast_start_sample(1)); stop=double(T.broadcast_end_sample_exclusive(1));
C=double(T{:,{'native_symbol_index_from_burst','native_subcarrier_start','native_subcarrier_count', ...
    'cp_start_sample','useful_start_sample','useful_end_sample_exclusive'}});
assert(all(isfinite([fs scs origin stop])) && fs>0 && scs>0 && ...
    origin>=0 && stop>origin && all([origin stop]==fix([origin stop])) && ...
    all(isfinite(C)&C==fix(C),'all') && all(C(:,1)>=0 & C(:,1)<T.grid_symbol_count & ...
    C(:,2)>=0 & C(:,3)>0 & C(:,2)+C(:,3)<=T.grid_subcarrier_count & ...
    C(:,4)>=origin & C(:,5)>C(:,4) & C(:,6)<=stop & C(:,6)-C(:,5)==fs/scs), ...
    'sixgr:truth:SSBIntervalClock','Native SSB CP/useful intervals must lie on the emitted sample clock.');
f=double(T.frequency_first_hz); last=double(T.frequency_last_hz);
offset=unique(f-C(:,2)*scs);
assert(all(isfinite([f;last])) && numel(offset)==1 && ...
    all(last==f+(C(:,3)-1)*scs),'sixgr:truth:SSBIntervalFrequency', ...
    'Native bin coordinates disagree with the retained frequency plane.');
gridRB=double(carrier.NSizeGrid); commonSCS=1000*double(carrier.SubcarrierSpacing);
lower=((0:gridRB-1)*12-6*gridRB-.5)*commonSCS; upper=lower+12*commonSCS;
symbols=unique(C(:,1),'sorted');
assert(numel(symbols)==4 && all(diff(symbols)==1),'sixgr:truth:SSBIntervalSymbols', ...
    'One normal SS/PBCH block must retain four consecutive native symbols.');
rows=repmat(struct('StartSample',NaN,'EndSampleExclusive',NaN,'SampleRateHz',fs, ...
    'NativeSymbolIndex0',NaN,'CarrierPRBIntersectionSet0Based',[]),numel(symbols),1);
for k=1:numel(symbols)
    selected=C(:,1)==symbols(k); clock=unique(C(selected,4:6),'rows');
    assert(size(clock,1)==1,'sixgr:truth:SSBIntervalClock','Ports/components disagree on SSB symbol timing.');
    occupied=false(1,gridRB); runs=unique([f(selected)-scs/2,last(selected)+scs/2],'rows');
    for j=1:size(runs,1)
        occupied=occupied | (upper>runs(j,1) & lower<runs(j,2));
    end
    assert(any(occupied),'sixgr:truth:SSBIntervalFrequency','SSB has no carrier-band intersection.');
    rows(k).StartSample=clock(1); rows(k).EndSampleExclusive=clock(3);
    rows(k).NativeSymbolIndex0=symbols(k);
    rows(k).CarrierPRBIntersectionSet0Based=find(occupied)-1;
end
assert(all([rows(2:end).StartSample]==[rows(1:end-1).EndSampleExclusive]), ...
    'sixgr:truth:SSBIntervalClock','Native SSB symbols must be consecutive on the sample clock.');
evidence.ExecutedSampleIntervalsJSON=string(jsonencode(rows));
evidence.ExecutedSampleIntervalSource="executed_native_SSB_CP_useful_samples_not_RF_activity";
evidence.ResourceGridPRBCount=gridRB;
evidence.NativeAllocationID=string(T.allocation_id(1));
evidence.NativeGridSHA256=string(T.transmit_grid_sha256(1));
end
