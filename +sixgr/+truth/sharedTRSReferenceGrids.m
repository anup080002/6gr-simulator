function [grids,evidence]=sharedTRSReferenceGrids(prepared,captures,replay,det)
% Scoring only: SAME executed NR fading snapshots, never receiver inputs.
assert(iscell(captures) && ~isempty(captures) && isfield(prepared,'TransmitStartSample') && ...
    isfield(prepared,'TransmitProjectionMatrix'),'sixgr:truth:MissingTRSChannelScoring', ...
    'Retain physical TX mapping/origin and actual channel references.');
first=captures{1}; base=first.Reference; next=base.StartSample;
gains=cell(size(captures)); times=gains; W=prepared.TransmitProjectionMatrix;
for k=1:numel(captures)
    c=captures{k}; r=c.Reference;
    assert(c.LinkID==first.LinkID && c.TX==first.TX && c.RX==first.RX && ...
        sixgr.channel.isAppliedChannelReference(r) && r.Source==base.Source && ...
        r.StartSample==next && size(r.PathGains,1)==r.EndSampleExclusive-r.StartSample && ...
        r.SampleRateHz==prepared.SampleRateHz && r.StateKey==base.StateKey && ...
        isequal(r.PathFilters,base.PathFilters) && r.NormalizeChannelOutputs==base.NormalizeChannelOutputs && ...
        r.NumTransmitAntennas==size(W,1) && r.NumReceiveAntennas==base.NumReceiveAntennas && ...
        r.AdditionalChannelExecutions==0 && ~r.ReceiverEstimatorInput, ...
        'sixgr:truth:IncompleteTRSChannelScoring','Do not replace gaps, links, ports or applied channel coefficients.');
    gains{k}=r.PathGains; times{k}=r.SampleTimes_s; next=r.EndSampleExclusive;
end
gains=cat(1,gains{:}); times=vertcat(times{:});
assert(all(abs(diff(times)*prepared.SampleRateHz-1)<1e-6), ...
    'sixgr:truth:TRSReferenceSampleClock','Channel snapshots must cover every actual sample.');
amplitude=double(prepared.PowerContext.AmplitudeScale);
loss=10^(double(replay.AppliedLargeScaleGain_dB)/20);
assert(isfinite(amplitude) && amplitude>0 && isfinite(loss) && loss>0, ...
    'sixgr:truth:MissingTRSScoringPower','Retain declared TX scaling and actual applied loss.');
normalization=1;
if base.NormalizeChannelOutputs, normalization=1/sqrt(base.NumReceiveAntennas); end
grids=cell(numel(det.SlotDetections),1); evidence=grids;
for k=1:numel(grids)
    d=det.SlotDetections(k);
    nominal=prepared.TransmitStartSample+prepared.Tx.SlotTable.StartSample1Based(k)-1;
    offset=double(det.Table.EstimatedTimingOffset_samples(k));
    count=size(d.CorrectedWaveform,1); origin=nominal-base.StartSample;
    assert(origin>=0 && origin==fix(origin) && isfinite(offset) && offset>=0 && ...
        offset==fix(offset) && offset<size(base.PathFilters,1) && count>0 && ...
        next>=nominal+offset+count,'sixgr:truth:TRSReferenceTimingCoverage', ...
        'Applied coefficients must cover each measured FFT window without extrapolating its samples.');
    carrier=prepared.Tx.GridSlots(k).Carrier;
    L=size(d.RxGrid,2); K=size(d.RxGrid,1); R=size(d.RxGrid,3);
    nfft=double(prepared.Tx.OFDM.Nfft);
    assert(prepared.SampleRateHz==nfft*double(carrier.SubcarrierSpacing)*1000, ...
        'sixgr:truth:TRSReferenceResamplingUnsupported', ...
        'A resampled receiver requires its actual resampling operator for independent scoring.');
    firstSymbol=(double(prepared.Tx.SlotTable.Slot(k))-double(prepared.Tx.FirstSlot0Based))* ...
        double(carrier.SymbolsPerSlot);
    cp=double(prepared.Tx.OFDM.SymbolLengths(firstSymbol+(1:L)))-nfft;
    h=sixgr.truth.receivedFFTChannelDiagonal(gains(origin+1:end,:,:,:),base.PathFilters, ...
        nfft,cp,K,offset,d.CyclicPrefixFraction);
    assert(size(h,1)==K && size(h,2)>=L && size(h,3)==R && size(h,4)==size(W,1), ...
        'sixgr:truth:TRSReferenceGridShape','All scored symbols/RX branches/physical TX ports must exist.');
    h=h(:,1:L,:,:);
    grids{k}=reshape(reshape(h,[],size(W,1))*W,[K L R size(W,2)])*amplitude*loss*normalization;
    evidence{k}=struct('Source',"applied_channel_gain_truth_shared_NR_path_filter_reference", ...
        'ReferencePlane',"nominal_linear_TRS_port_response_with_executed_fading_loss_and_declared_TX_power", ...
        'RFImpairmentsIncluded',false,'ReceiverEstimatorInput',false, ...
        'TimingOffsetRelativeTX_samples',offset,'TXStartSample',nominal, ...
        'ReceiverAlignedStartSample',nominal+offset,'PortToElementMatrix',W, ...
        'TXAmplitudeScale',amplitude,'LargeScaleAmplitudeGain',loss, ...
        'ChannelOutputNormalizationGain',normalization,'ChannelReferenceSegmentCount',numel(captures), ...
        'ReferenceCalculation',"executed_sample_rate_operator_same_symbol_FFT_diagonal", ...
        'GainOrPhaseFitted',false,'AdditionalChannelExecutions',0);
    if base.Source=="executed_identity_AWGN_operator"
        evidence{k}.Source="applied_identity_AWGN_operator_TRS_port_reference";
    end
end
end
