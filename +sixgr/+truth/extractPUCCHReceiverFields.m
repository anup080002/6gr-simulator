function [report,layoutOK] = extractPUCCHReceiverFields(trial)
%EXTRACTPUCCHRECEIVERFIELDS Consume canonical RX fields, not TX serialization.
% This checks retained receiver-output consistency, not gNB schedule identity
% or actual PHY execution. The caller must still validate both independently.
required = {'Receiver','ReceiverFields','ReceiverExpectedBitCount', ...
    'ReceiverExpectedHARQBitCount','ReceiverExpectedSRBitCount', ...
    'ReceiverExpectedCSIPart1BitCount','ReceiverExpectedCSIPart2BitCount'};
assert(isstruct(trial) && isscalar(trial) && all(isfield(trial,required)), ...
    'sixgr:truth:MissingPUCCHReceiverFields','Retain canonical receiver fields and receiver-owned lengths.');
counts = [trial.ReceiverExpectedHARQBitCount, trial.ReceiverExpectedSRBitCount, ...
    trial.ReceiverExpectedCSIPart1BitCount, trial.ReceiverExpectedCSIPart2BitCount];
total = trial.ReceiverExpectedBitCount;
validateattributes(counts,{'numeric'},{'real','finite','integer','nonnegative','numel',4});
validateattributes(total,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
counts=double(counts); total=double(total);
assert(total>=sum(counts),'sixgr:truth:InvalidPUCCHReceiverLayout', ...
    'Receiver wire length cannot be smaller than its information fields.');
rx = trial.Receiver;
assert(isstruct(rx) && isscalar(rx) && ...
    all(isfield(rx,{'DecodedSequence1','DecodedSequence2','DecodedFields'})) && ...
    isequaln(trial.ReceiverFields,rx.DecodedFields), ...
    'sixgr:truth:InconsistentPUCCHReceiverFields','Trial fields must be the retained canonical receiver output.');
one = localBits(rx.DecodedSequence1);
two = localBits(rx.DecodedSequence2);
fields = rx.DecodedFields;
assert(isstruct(fields) && isscalar(fields) && ...
    all(isfield(fields,{'HARQACK','SR','CSIPart1','CSIPart2'})), ...
    'sixgr:truth:MissingPUCCHReceiverFields','Retain every owned receiver field, including empty ones.');
harq = localBits(fields.HARQACK); sr = localBits(fields.SR);
csi1 = localBits(fields.CSIPart1); csi2 = localBits(fields.CSIPart2);
layoutOK = numel(one)==sum(counts(1:3)) && ...
    numel(one)+numel(two)==total && ...
    isequal([numel(harq),numel(sr),numel(csi1),numel(csi2)],counts);
padding = int8(zeros(0,1));
if layoutOK
    assert(isequal(one,[harq;sr;csi1]) && isequal(two(1:counts(4)),csi2), ...
        'sixgr:truth:InconsistentPUCCHReceiverFields','Decoded fields disagree with their canonical wire sequences.');
    padding = two(counts(4)+1:end);
end
report = struct('InformationBits',[harq;sr;csi1;csi2], ...
    'HARQACKBits',harq,'SRBits',sr,'CSIPart1Bits',csi1, ...
    'CSIPart2Bits',csi2,'PaddingBits',padding);
end

function bits = localBits(value)
assert((isnumeric(value)||islogical(value)) && isreal(value) && ...
    (isvector(value)||isempty(value)) && all(isfinite(value(:))) && ...
    all(value(:)==0 | value(:)==1),'sixgr:truth:InvalidReceivedHARQBit', ...
    'Received fields must contain actual binary values before conversion.');
bits = int8(value(:));
end
