function provenance = captureReceivedCSIProvenance(report, decisionClock)
%CAPTURERECEIVEDCSIPROVENANCE Retain receiver-only lineage, never UE audit.
% This is a value-boundary check, not evidence that a physical decoder ran.
% Missing historical sample metadata remains unbound. Configured reference
% slots are not asserted to be the UE's measurement occasion.
if nargin<2, decisionClock=struct(); end
provenance=struct();
if ~isequal(sixgr.util.structGet(report,'CSIUCIDecodeOk',false),true) || ...
        string(sixgr.util.structGet(report,'SourceSignal',""))~="received_CSI_UCI"
    return;
end
provenance.Version="received_csi_provenance/v1";
provenance.Source="independently_received_CSI_report_projection";
textFields=["Direction","ReportIdentity","CSIReportConfigID","CSIUCIChannel", ...
    "CSIUCITransport","SourceSlotAuthority","ObservationID","ReceiverContextDigest", ...
    "ReceiverClockDomain","CSIUCIDecodedBitsToken","RunID","ExecutionID", ...
    "ConfigHash","ScenarioID","PopulationIdentitySource"];
numberFields=["UEIndex","RNTI","ServingCell","CSIConfigurationEpoch", ...
    "SourceSlot","DueSlot","DeliveredSlot","CSIReferenceSlot", ...
    "CQI","RI","PMI","LI","CRI","PMI_I11","PMI_I12","PMI_I13","PMI_I2", ...
    "CSIUCIDecodedBitCount","ReceiverClockEpoch","ObservationStartSample", ...
    "ObservationEndSampleExclusive","ObservationSampleRateHz","AvailableAtSample", ...
    "RandomSeed","ChannelSeed","SweepPointIndex","ConfiguredSNR_dB"];
for field=textFields, provenance.(field)=string(sixgr.util.structGet(report,field,"")); end
for field=numberFields, provenance.(field)=double(sixgr.util.structGet(report,field,NaN)); end
provenance.ReceiverObservationBound=false;
provenance.ReferenceAttributionQualified=false;
provenance.BindingStatus="historical_receiver_sample_context_unavailable";
requiredText=["ReportIdentity","ObservationID","ReceiverContextDigest","ReceiverClockDomain"];
requiredNumbers=["ReceiverClockEpoch","ObservationStartSample", ...
    "ObservationEndSampleExclusive","ObservationSampleRateHz","AvailableAtSample"];
complete=all(arrayfun(@(f)isscalar(provenance.(f)) && ...
    strlength(provenance.(f))>0,requiredText)) && ...
    all(arrayfun(@(f)isnumeric(provenance.(f)) && isscalar(provenance.(f)) && ...
    isfinite(provenance.(f)),requiredNumbers));
provenance.ReceiverObservationMetadataComplete=complete;
if ~complete, return; end
assert(provenance.ObservationStartSample>=0 && ...
    provenance.ObservationStartSample==fix(provenance.ObservationStartSample) && ...
    provenance.ObservationEndSampleExclusive>provenance.ObservationStartSample && ...
    provenance.ObservationEndSampleExclusive==fix(provenance.ObservationEndSampleExclusive) && ...
    provenance.AvailableAtSample>=provenance.ObservationEndSampleExclusive && ...
    provenance.AvailableAtSample==fix(provenance.AvailableAtSample) && ...
    provenance.ObservationSampleRateHz>0, ...
    'sixgr:truth:InvalidCSIProvenanceClock','Retain the completed receiver sample interval.');
if isempty(fieldnames(decisionClock)), return; end
assert(all(isfield(decisionClock,{'ClockDomain','ClockEpoch','SampleRateHz','AtSample'})) && ...
    string(decisionClock.ClockDomain)==provenance.ReceiverClockDomain && ...
    isequal(decisionClock.ClockEpoch,provenance.ReceiverClockEpoch) && ...
    isequal(decisionClock.SampleRateHz,provenance.ObservationSampleRateHz), ...
    'sixgr:truth:CSIProvenanceClockMismatch','CSI and its consumer must use the same owner clock.');
assert(isscalar(decisionClock.AtSample) && isfinite(decisionClock.AtSample) && ...
    decisionClock.AtSample==fix(decisionClock.AtSample) && ...
    provenance.AvailableAtSample<=decisionClock.AtSample, ...
    'sixgr:truth:FutureCSIProvenance','A grant decision cannot consume future received CSI.');
provenance.ReceiverObservationBound=true;
provenance.BindingStatus="received_observation_available_on_same_owner_clock";
end
