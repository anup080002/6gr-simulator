function [grid,evidence,unmatchedGrid,unmatchedEvidence]=sharedDataScoringWaveformReference(snapshot,prepared,observation,scoringEvidence)
% Exact post-reception effective DM-RS reference from the executed link IQ.
% The practical receiver never sees this noiseless scoring plane.  This
% function executes no channel or RF model and fits no gain or phase.
arguments
    snapshot (1,1) struct
    prepared
    observation
    scoringEvidence (1,1) struct
end
channel="PUSCH";
if prepared.Direction=="DL", channel="PDSCH"; end
isolated=~isa(prepared,'sixgr.link.PreparedDataTransmission');
if isa(prepared,'sixgr.link.PreparedDataTransmission')
    assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && ...
        observation.isComplete() && observation.SampleRateHz==prepared.SampleRateHz && ...
        observation.StartSample==prepared.ReceiveStartSample, ...
        'sixgr:truth:InvalidDataScoringWaveformReference', ...
        'The shared scoring buffer must cover the executed receiver window.');
    wave=observation.readComplete();
    startSample=observation.StartSample;
else
    % The isolated runner retains the same executed desired-link samples
    % before noise/interference/RX RF, rather than reconstructing a channel.
    assert(isstruct(prepared) && isscalar(prepared) && ...
        prepared.Contract=="isolated_executed_data_scoring/v1" && ...
        any(prepared.Direction==["DL","UL"]) && prepared.ReceiveStartSample==0 && ...
        isnumeric(observation) && isfloat(observation) && ismatrix(observation) && ...
        string(scoringEvidence.WaveformSHA256)==string( ...
            sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(observation)), ...
        'sixgr:truth:InvalidIsolatedDataScoringWaveform', ...
        'Retain and identify the actual isolated receive-window samples.');
    wave=observation;
    startSample=0;
    assert(isfield(scoringEvidence,'RecordedReceiverTimingOffset_samples'), ...
        'sixgr:truth:MissingDataScoringTimingReplay', ...
        'Isolated scoring requires the executed RX timing clock, not a configured substitute.');
    delay=double(scoringEvidence.RecordedReceiverTimingOffset_samples);
    validateattributes(delay,{'numeric'},{'scalar','real','finite'});
    wave=sixgr.util.applyFractionalSampleDelay(wave,delay);
end
assert(snapshot.Contract==channel+"_pilot_channel_capture/v1" && ...
    ~logical(scoringEvidence.ReceiverEstimatorInput) && ...
    double(scoringEvidence.AdditionalChannelExecutions)==0 && ...
    double(scoringEvidence.AdditionalRFExecutions)==0, ...
    'sixgr:truth:InvalidDataScoringWaveformReference', ...
    'Use the complete independently retained desired-link waveform on the actual receive clock.');

op=snapshot.ReceiverChannelOperator;
required={'ReceiveCombiningMatrix','CaptureOriginCFOCorrection_Hz', ...
    'AlignedOriginCFOCorrection_Hz','AppliedTimingCorrection_samples','SampleRateHz'};
assert(all(isfield(op,required)) && double(op.SampleRateHz)==prepared.SampleRateHz, ...
    'sixgr:truth:MissingDataScoringReceiverOperator', ...
    'Retain the actual timing, frequency and spatial receiver operations.');
assert(~isempty(wave) && all(isfinite(wave),'all'), ...
    'sixgr:truth:InvalidDataScoringWaveform','The executed desired-link samples must be finite.');
fs=double(prepared.SampleRateHz);
first=double(op.AppliedTimingCorrection_samples);
validateattributes(first,{'numeric'},{'scalar','real','finite','>',-size(wave,1),'<',size(wave,1)});
policy=string(sixgr.util.structGet(op,'TimingApplicationPolicy',""));
clockAligned=false;
if ~isolated && isfield(scoringEvidence,'ReceiverClockExecution')
    assert(policy=="actual_capture_complete_slot_extraction_no_padding", ...
        'sixgr:truth:UnsupportedSharedScoringTimingPolicy', ...
        'Shared scoring must use the actual retained capture extraction.');
    validateattributes(first,{'numeric'},{'integer','nonnegative'});
    [wave,clockEvidence]=sixgr.truth.sharedReceiverClockScoringWindow( ...
        observation,scoringEvidence,scoringEvidence.ReceiverClockExecution, ...
        startSample+first,size(wave,1)-first);
    delay=clockEvidence.RecordedReceiverTimingOffset_samples;
    startSample=startSample+first;
    clockAligned=true;
end
absolute=(startSample:startSample+size(wave,1)-1).';
% The retained contribution precedes RX RF. Add its executed RX oscillator
% BEFORE reproducing receiver corrections. TX CFO is already in these IQs.
% Preserve the old, frequency-unmatched comparison as a separate diagnostic.
unmatchedWave=wave;
assert(isfield(scoringEvidence,'ReceiverClockExecution'), ...
    'sixgr:truth:MissingScoringRXFrequencyExecution','Retain actual RX oscillator execution for independent scoring.');
[wave,frequencyEvidence]=sixgr.truth.applyExecutedReceiverFrequencyForScoring( ...
    wave,fs,startSample,scoringEvidence.ReceiverClockExecution);
wave=localReceiverOperations(wave,op,fs,absolute,prepared.ReceiveStartSample,first,policy,clockAligned);
[grid,ofdm,info]=localEstimate(wave,snapshot,prepared,channel);
unmatchedGrid=[];
if nargout>2
    unmatchedWave=localReceiverOperations(unmatchedWave,op,fs,absolute,prepared.ReceiveStartSample,first,policy,clockAligned);
    unmatchedGrid=localEstimate(unmatchedWave,snapshot,prepared,channel);
end
evidence=struct('Source',"same_executed_desired_link_waveform_post_decode_"+channel+"_DMRS_LS", ...
    'ReferencePlane',"effective_"+channel+"_layer_channel_on_recorded_RX_clock_with_executed_RX_CFO_and_received_correction_before_other_RX_RF", ...
    'AppliedChannelSource',"actual_executed_link_contribution", ...
    'RFImpairmentsIncluded',true,'ReceiverEstimatorInput',false, ...
    'GainOrPhaseFitted',false,'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0, ...
    'TimingOffsetRelativeReceiveWindow_samples',first, ...
    'ReceiveCombiningMatrix',double(op.ReceiveCombiningMatrix),'ScoringEvidence',scoringEvidence, ...
    'ScoringOFDMInfo',ofdm,'ScoringEstimatorInfo',info, ...
    'ReferenceScope',"receiver_retained_DMRS_resources_from_same_executed_noiseless_link_IQ", ...
    'FrequencyEvidence',frequencyEvidence,'ReceiverCFOIncluded',true, ...
    'ExecutedReceiverCFO_Hz',frequencyEvidence.ExecutedReceiverCFO_Hz, ...
    'ResidualOscillatorQualification',false,'TimingApplicationPolicy',policy);
if isolated || clockAligned
    evidence.RecordedReceiverTimingOffset_samples=delay;
    evidence.ReceiverTimingIncluded=true;
end
unmatchedEvidence=evidence;
unmatchedEvidence.ReferencePlane="pre_RX_oscillator_reference_with_receiver_correction_frequency_unmatched_diagnostic";
unmatchedEvidence.ReceiverCFOIncluded=false;
unmatchedEvidence.ComparisonRole="legacy_frequency_unmatched_comparison_not_channel_estimation_quality";
unmatchedEvidence=rmfield(unmatchedEvidence,{'FrequencyEvidence','ExecutedReceiverCFO_Hz'});
end

function wave=localReceiverOperations(wave,op,fs,absolute,receiveStart,first,policy,clockAligned)
phase=-2*pi/fs*double(op.CaptureOriginCFOCorrection_Hz).* ...
    (absolute-receiveStart);
wave=wave.*cast(exp(1i*phase),'like',wave);
B=double(op.ReceiveCombiningMatrix);
assert(size(B,1)==size(wave,2) && all(isfinite(B),'all'), ...
    'sixgr:truth:InvalidDataScoringReceiveCombiner', ...
    'The scoring waveform must use the executed receive spatial projection.');
wave=wave*cast(conj(B),'like',wave);
% Reproduce the actual receiver operation: standalone signed correction
% preserves length; bounded shared capture extraction must not pad samples.
if clockAligned
    % Already selected the exact reference samples for this receiver window.
elseif startsWith(policy,"signed_waveform_shift") || ...
        any(policy==["timing_estimation_bypassed_no_runtime_correction", ...
        "timing_estimate_unavailable_no_runtime_correction"])
    wave=sixgr.util.applyFractionalSampleDelay(wave,-first);
elseif policy=="actual_capture_complete_slot_extraction_no_padding"
    validateattributes(first,{'numeric'},{'integer','>=',0});
    wave=wave(first+1:end,:);
else
    error('sixgr:truth:MissingDataScoringTimingPolicy', ...
        'The scoring reference requires the actual executed receiver timing policy.');
end
% The second frequency operation is applied AFTER timing alignment in the
% UL receiver. Preserve that order for fractional interpolation as well.
phase=-2*pi/fs*double(op.AlignedOriginCFOCorrection_Hz).*(0:size(wave,1)-1).';
wave=wave.*cast(exp(1i*phase),'like',wave);
end

function [grid,ofdm,info]=localEstimate(wave,snapshot,prepared,channel)
[referenceRxGrid,ofdm]=sixgr.phy.waveform.ofdmDemodulate(snapshot.Carrier,wave);
shape=double(snapshot.GridShape);
assert(size(referenceRxGrid,1)==shape(1) && size(referenceRxGrid,2)>=shape(2) && ...
    size(referenceRxGrid,3)==shape(3), ...
    'sixgr:truth:DataScoringOFDMClockMismatch', ...
    'The independently scored waveform must reproduce the receiver FFT grid.');
referenceRxGrid=referenceRxGrid(:,1:shape(2),:);
channelModel=string(sixgr.util.structGet(prepared.InputConfig,'channel.model','AWGN'));
[grid,~,info]=sixgr.phy.rx.channelEstimate(snapshot.Carrier,referenceRxGrid, ...
    snapshot.PilotIndices,snapshot.PilotSymbols,'UseFastMex',false, ...
    'StrictMode',true,'ChannelModel',channelModel, ...
    'ExpectedTxPorts',shape(4),'Method',"LS", ...
    'ContextLabel',channel+"_post_decode_scoring_reference");
assert(isequal([size(grid,1) size(grid,2) size(grid,3) size(grid,4)],shape) && ...
    all(isfinite(grid),'all'), ...
    'sixgr:truth:IncompleteDataScoringChannelReference', ...
    'The noiseless pilot estimator must retain every effective port and receive branch.');
end
