function plans=buildCellMsg3ReceivePlans(prepared,proof,calendar,armedAtSample)
% No UE state/TX/capture is an input.
% This pure planner does not establish that proof came from an actual owner;
% CoupledWaveformStream must first retrieve its exact private CellRARTX
% completion and compare prepared/proof before calling this function.
id='sixgr:truth:CellMsg3ReceiveAuthority';
assert(prepared.ContractVersion=="prepared_cell_RAR/v1" && ...
    proof.ContractVersion=="executed_cell_RAR_component/v1" && ...
    proof.PhysicalTransmissionVerified && ~proof.ReceiverExecutionClaimed && ...
    proof.ServingCell==calendar.CellID && ...
    proof.CellCalendarSHA256==calendar.SHA256 && ...
    proof.RARPlanSHA256==prepared.RARPlan.PlanSHA256 && ...
    proof.RARPayloadSHA256==sixgr.protocol.ProtocolHash.bytes(prepared.Tx.RAR.Bytes) && ...
    proof.CompletedAtSample==armedAtSample,id,'Bind one original emitted cell RAR.');
cfg=prepared.Config;ra=prepared.RAContext;
policy=sixgr.lls6g.config.resolveNRAccessPolicy(sixgr.util.structGet(cfg,'initial_access.rrc',struct()));
assert(policy.Enabled&&policy.EncodingProfile=="nr_rrc_access_base_srb1_uper_v1", ...
    'sixgr:truth:CellMsg3NRCodecRequired', ...
    'Independent Msg3 reception needs complete received MAC/NR bytes, not TX-private length.');
assert(ra.ServingCell==calendar.CellID&&ra.UEId==0 && ...
    ra.ContextSHA256==string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(rmfield(ra,'ContextSHA256'))))), ...
    id,'Retain the cell-owned response context; never substitute a matched UE continuation.');
% Decode the actual emitted MAC RAR payload against original gNB common
% context. All RAPIDs remain independent receive hypotheses. Reception of
% RAR by a UE and presence of any later UE transmitter are not prerequisites.
rar=sixgr.mac.ra.decodeMACRAR(prepared.Tx.RAR.Bytes,ra);
assert(numel(rar.Responses)==numel(prepared.RARPlan.Assignments),id,'Retain the complete emitted response population.');
serving=calendar.ConfiguredSIB1Tree.message.c1.systemInformationBlockType1.servingCellConfigCommon;
present=isfield(serving,'n_TimingAdvanceOffset');ie="";
if present,ie=string(serving.n_TimingAdvanceOffset);end
range=string(sixgr.util.structGet(cfg,'frequency.range_name',sixgr.util.structGet(cfg,'phy.prach.frequencyRange',"")));
offset=sixgr.phy.frame.resolveULTimingAdvanceOffsetValue(present,ie,range);
fs=calendar.Receiver.SampleRateHz;tc=double(sixgr.phy.frame.AbsoluteTime.TicksPerSecond)/fs;
assert(tc==fix(tc)&&rem(offset.NTAOffset_Tc,int64(tc))==0,id,'Common receive origin must lie on the original physical sample clock.');
guard=calendar.Receiver.SearchGuardSamples;tail=calendar.Receiver.FilterTailSamples;
plans=cell(numel(rar.Responses),1);
for k=1:numel(rar.Responses)
    response=rar.Responses(k);grant=response.ULGrant;
    assignment=prepared.RARPlan.Assignments([prepared.RARPlan.Assignments.RAPID]==response.RAPID);
    assert(isscalar(assignment)&&assignment.TemporaryCRNTI==response.TemporaryCRNTI,id,'Do not invent a receiver RNTI from a UE ordinal.');
    context=ra;context.TempCRNTI=response.TemporaryCRNTI;
    context.RRCEncodingProfile=policy.EncodingProfile;
    a=sixgr.phy.ra.resolveMsg3PUSCHAllocation(cfg,context,grant);
    nominal=sixgr.phy.frame.slotStartSample(a.Carrier,a.AbsoluteSlot,fs);
    nominalStop=sixgr.phy.frame.slotStartSample(a.Carrier,a.AbsoluteSlot+1,fs);
    center=nominal-double(offset.NTAOffset_Tc)/tc;
    first=center-guard;stop=center+(nominalStop-nominal)+guard+tail;
    assert(first>=armedAtSample&&first>=0&&stop>first,id, ...
        'Arm the whole original gNB observation before its first sample; never align to a UE transmitter.');
    plan=struct('ContractVersion',"cell_Msg3_receive_plan/v1", ...
        'ServingCell',calendar.CellID,'PhysicalCellID',calendar.PhysicalCellID, ...
        'RARComponentID',proof.ComponentID,'RAPID',response.RAPID, ...
        'TemporaryCRNTI',response.TemporaryCRNTI,'OriginalRARResponse',response, ...
        'RARPayloadSHA256',proof.RARPayloadSHA256,'RARPlanSHA256',proof.RARPlanSHA256, ...
        'CellCalendarSHA256',calendar.SHA256,'RAContext',context,'Grant',grant, ...
        'AbsoluteSlot0',a.AbsoluteSlot,'TransportBlockSize',a.TransportBlockSize, ...
        'ResourceAccounting',a.ResourceAccounting,'NominalStartSample',nominal, ...
        'ReceiveStartSample',first,'ReceiveEndSampleExclusive',stop,'SampleRateHz',fs, ...
        'NumReceiveAntennas',calendar.Receiver.NumReceiveAntennas, ...
        'FilterDelaySamples',calendar.FilterDelaySamples,'FilterTailSamples',tail, ...
        'CommonOffset',offset,'SearchGuardSamples',guard,'SearchGuardSource',calendar.SearchGuardSource, ...
        'ArmedAtSample',armedAtSample,'PhysicalConfigurationEpoch',proof.PhysicalConfigurationEpoch, ...
        'UETransmissionRequired',false,'UEReceivedRARRequired',false, ...
        'ReceiveWindowSource',"original_gNB_slot_common_offset_configured_search_guard_filter_tail", ...
        'Scope',"cell_original_emitted_RAR_grant_to_receive_plan_not_Msg3_decode");
    plan.SHA256=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(plan))));
    plans{k}=plan;
end
end
