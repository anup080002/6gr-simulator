function path=exportPUCCHPowerAdmissionDiagnostics(state,runFolder)
% Export original UE no-transmission decisions, never receiver outcomes.
% This immutable audit is separate from pucch_trials and received CSI/HARQ.
% It does not infer DTX, CRC, delivery, or radio execution from admission.
arguments
    state (1,1) struct
    runFolder (1,1) string
end
path="";
if ~isfield(state,'SharedPUCCHPowerAdmissionTable'), return; end
T=state.SharedPUCCHPowerAdmissionTable;
assert(istable(T),'sixgr:truth:PUCCHAdmissionExportSchema', ...
    'Original PUCCH admission evidence must be a table.');
if height(T)==0, return; end
required=["UEIndex","ServingCell","DecisionSlot","PUCCHResourceSlot", ...
    "MeasuredPowerReferenceRequired","PreparationAdmitted","PowerReferenceStatus","Action", ...
    "PowerReferenceRS","PowerReferenceSignalID","MaximumPowerReferenceAgeSlots", ...
    "PowerReferenceMeasurementID","PowerReferenceProducerSlot","PowerReferenceAvailableSlot", ...
    "MeasuredPathloss_dB","Source","EvidenceClass","RNTI","ComponentCarrier","ActiveULBWP", ...
    "PhysicalOccasionID","ObservationID","DecisionSample","ClockEpoch","SampleRateHz", ...
    "PUCCHGrantIDsJSON","CSIReportIdentitiesJSON","SelectedGNBTransport", ...
    "UETransmissionPrepared","UEProducerDisposition"];
names=string(T.Properties.VariableNames);
assert(all(ismember(required,names)), 'sixgr:truth:PUCCHAdmissionExportSchema', ...
    'A deferral export must retain the original admission, clock and owner identities.');
forbidden=["DTX","DTXFlag","CRCPass","CSIUCIDecodeOk","CSIUCICRCPass", ...
    "ACK","NACK","Processed","DeliveredSlot","ReceiverCompletionObserved","CompletionSample", ...
    "WaveformExecuted","GrantExecutedFlag"];
assert(~any(ismember(forbidden,names)), 'sixgr:truth:PUCCHAdmissionExportScope', ...
    'Receiver/delivery outcomes belong to their actual observation tables, not UE admission.');
for name=["UEIndex","ServingCell","DecisionSlot","PUCCHResourceSlot","RNTI"]
    localNumber(T,name,false,1,true);
end
for name=["ComponentCarrier","ActiveULBWP","DecisionSample","ClockEpoch","PowerReferenceSignalID"]
    localNumber(T,name,false,0,true);
end
for name=["PowerReferenceProducerSlot","PowerReferenceAvailableSlot"]
    localNumber(T,name,true,1,true);
end
localNumber(T,"MeasuredPathloss_dB",true,-Inf,false);
localNumber(T,"SampleRateHz",false,0,false);
age=T.MaximumPowerReferenceAgeSlots;
assert(isnumeric(age)&&isreal(age)&&isequal(size(age),[height(T),1])&& ...
    all((isfinite(age)&age>=0)|(isinf(age)&age>0)), ...
    'sixgr:truth:PUCCHAdmissionExportOperands','Preserve a valid original maximum reference age.');
assert(all(T.SampleRateHz>0)&&all(T.DecisionSlot<=T.PUCCHResourceSlot), ...
    'sixgr:truth:PUCCHAdmissionExportOperands','Invalid original admission clock.');
for name=["MeasuredPowerReferenceRequired","PreparationAdmitted","UETransmissionPrepared"]
    assert(islogical(T.(name))&&isequal(size(T.(name)),[height(T),1]), ...
        'sixgr:truth:PUCCHAdmissionExportOperands','Admission flags must retain original logical types.');
end
assert(all(T.MeasuredPowerReferenceRequired)&~any(T.PreparationAdmitted)&~any(T.UETransmissionPrepared), ...
    'sixgr:truth:PUCCHAdmissionExportScope','This table records only original required-reference deferrals.');
for name=["PowerReferenceStatus","Action","PowerReferenceRS","PowerReferenceMeasurementID", ...
        "Source","EvidenceClass","PhysicalOccasionID","ObservationID","PUCCHGrantIDsJSON", ...
        "CSIReportIdentitiesJSON","SelectedGNBTransport","UEProducerDisposition"]
    v=T.(name);
    assert(isstring(v)&&isequal(size(v),[height(T),1])&&~any(ismissing(v)), ...
        'sixgr:truth:PUCCHAdmissionExportOperands','Preserve original scalar text, not numeric text casts.');
    if name~="PowerReferenceMeasurementID"
        assert(all(strlength(v)>0),'sixgr:truth:PUCCHAdmissionExportOperands','Missing original admission text.');
    end
end
assert(all(T.Source=="original_PUCCH_reference_preparation_admission")&& ...
    all(T.EvidenceClass=="preparation_admission_not_PHY_execution")&& ...
    all(T.Action=="defer_PUCCH_unavailable_measured_power_reference")&& ...
    all(T.UEProducerDisposition=="closed_untransmitted_missing_measured_power_reference")&& ...
    all(ismember(T.SelectedGNBTransport,["PUCCH","PUSCH"]))&& ...
    all(ismember(T.PowerReferenceStatus,["no_measurements","no_matching_measurement", ...
    "future_measurement_not_available","stale","no_available_decoded_sib1_power", ...
    "reference_lifecycle_unavailable"])), ...
    'sixgr:truth:PUCCHAdmissionExportScope','Do not convert other failures or outcomes into power deferrals.');
for k=find(T.PowerReferenceStatus=="reference_lifecycle_unavailable")'
    localLifecycle(T(k,:));
end
assert(numel(unique(T.ObservationID))==height(T), ...
    'sixgr:truth:PUCCHAdmissionExportIdentity','One original observation has one immutable decision.');
for k=1:height(T)
    grants=localIdentities(T.PUCCHGrantIDsJSON(k));
    reports=localIdentities(T.CSIReportIdentitiesJSON(k));
    assert(all(ismember("PUCCH-CSI-"+reports,grants)), ...
        'sixgr:truth:PUCCHAdmissionExportIdentity','Original CSI payloads must retain their own grant IDs.');
end
if ~sixgr.util.persistenceEnabled(), return; end
layout=sixgr.report.resultLayout(runFolder);
path=string(fullfile(layout.ControlCSVDir,'pucch_power_admission.csv'));
% csvWriteTable owns content-aware unchanged-write reuse and serialization.
sixgr.util.csvWriteTable(path,T,'PreserveSchema',true,'RoundTripNumericText',true);
end

function localLifecycle(row)
id='sixgr:truth:PUCCHAdmissionExportScope';
assert(all(ismember(["PathlossReferenceLifetime","ReferenceLifecycleStatus"], ...
    string(row.Properties.VariableNames))),id,'Retain the original unavailable lifecycle decision.');
for name=["PathlossReferenceLifetime","ReferenceLifecycleStatus"]
    assert(isstring(row.(name))&&isscalar(row.(name))&&~ismissing(row.(name)), ...
        id,'Keep original scalar lifecycle text.');
end
assert(row.PathlossReferenceLifetime=="retained_filtered_reference" && ...
    any(row.ReferenceLifecycleStatus==["no_received_reference_power_lifecycle", ...
    "reference_configuration_changed","serving_reference_not_synchronized", ...
    "decoded_common_reference_context_mismatch","decoded_common_reference_not_available", ...
    "decoded_common_physical_epoch_changed", ...
    "future_lifecycle_installation_not_available","received_power_change_not_installed", ...
    "missing_original_filtered_reference_context","no_observation_for_current_reference_power_generation"]), ...
    id,'An unknown or available lifecycle is not an operational reference deferral.');
end

function localNumber(T,name,allowNaN,minimum,integer)
v=T.(name);
assert(isnumeric(v)&&isreal(v)&&isequal(size(v),[height(T),1]), ...
    'sixgr:truth:PUCCHAdmissionExportOperands','Keep original scalar numeric operands.');
valid=isfinite(v)&v>=minimum;
if integer, valid=valid&v==fix(v)&v<=flintmax; end
if allowNaN, valid=valid|isnan(v); end
assert(all(valid),'sixgr:truth:PUCCHAdmissionExportOperands','Invalid original admission numeric operand.');
end

function ids=localIdentities(raw)
assert(startsWith(raw,"[")&&endsWith(raw,"]"), ...
    'sixgr:truth:PUCCHAdmissionExportIdentity','Identity lists must be original JSON arrays.');
try, value=jsondecode(char(raw));
catch, error('sixgr:truth:PUCCHAdmissionExportIdentity','Malformed original identity JSON.'); end
if isempty(value), ids=strings(0,1); return; end
assert(iscellstr(value)&&isvector(value), ...
    'sixgr:truth:PUCCHAdmissionExportIdentity','Identity arrays contain only original scalar strings.');
ids=string(value(:));
assert(all(strlength(ids)>0)&&numel(unique(ids))==numel(ids), ...
    'sixgr:truth:PUCCHAdmissionExportIdentity','Missing or duplicate original payload identity.');
end
