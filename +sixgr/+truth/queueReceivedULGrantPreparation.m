function state=queueReceivedULGrantPreparation(state,item,control)
% Defer preparation of an independently received and admitted UL command.
% Call only after normal PDCCH reception/admission has stored CONTROL in
% SharedReceivedGrantControls. ITEM is that original completed PDCCH item,
% not a scheduling intent or a future planning view. This handoff neither
% decodes control again nor prepares/transmits data, reserves queue bytes,
% or advances HARQ. The original receive path owns physical decode evidence.
arguments
    state (1,1) struct
    item (1,1) struct
    control (1,1) struct
end
owner=sixgr.util.structGet(state,'SharedWaveformStream',[]);
assert(isa(owner,'sixgr.truth.CoupledWaveformStream') && ...
    string(sixgr.util.structGet(state,'RuntimeViewMode',""))~="future_ul_grant_planning", ...
    'sixgr:truth:ReceivedULPreparationLiveOwnerRequired', ...
    'Use the live shared owner, never a future scheduler planning state.');
assert(string(sixgr.util.structGet(item,'Kind',""))=="PDCCH" && ...
    all(isfield(item,{'ID','UE','Context','Planes'})), ...
    'sixgr:truth:ReceivedULPreparationCompletionRequired', ...
    'The original completed PDCCH item is required.');
c=item.Context;
assert(isstruct(c) && isscalar(c) && ...
    all(isfield(c,{'Key','Grant','Prepared','UserCfg','Direction','Slot','ServingCell'})) && ...
    isstruct(control) && all(isfield(control, ...
    {'Key','Grant','Allowed','ReceivedAssignment','AvailableAtSample'})), ...
    'sixgr:truth:ReceivedULPreparationContextRequired','Retain the complete receive handoff.');
ue=double(item.UE);
validateattributes(ue,{'double'},{'scalar','finite','integer','positive','<=',state.NumUsers});
assert(iscell(c.UserCfg) && numel(c.UserCfg)>=ue && ...
    localTrue(control.Allowed) && upper(string(c.Direction))=="UL", ...
    'sixgr:truth:ReceivedULPreparationAdmissionRequired', ...
    'Only an admitted UL control may schedule UE data preparation.');
controls=sixgr.util.structGet(state,'SharedReceivedGrantControls',{});
hit=find(cellfun(@(x)string(x.Key)==string(control.Key),controls));
assert(isscalar(hit) && isequaln(controls{hit},control) && string(c.Key)==string(control.Key), ...
    'sixgr:truth:ReceivedULPreparationControlMismatch', ...
    'Use exactly one retained received control, not a copied or relabeled command.');
grant=control.Grant;
% Reuse the received-evidence guard, including the immutable grant identity
% and exact decoded/admitted field binding. Never replace grant operands.
bound=sixgr.truth.bindReceivedPDCCHGrantEvidence(c.Grant,grant);
% applyPDCCHGrantTrialImpl adds these receiver/admission status fields in
% addition to the shared received-evidence whitelist. No allocation, DCI,
% timing, PHYGrant or precoder operand may be changed or newly injected.
for name=["PDCCHReceiverDecodeOk","PDCCHDataAdmissionOk","PDCCHTCIAdmissionStatus"]
    if isfield(grant,name), bound.(name)=grant.(name); end
end
assert(isequaln(orderfields(bound),orderfields(grant)), ...
    'sixgr:truth:ReceivedULPreparationGrantOperandsChanged', ...
    'Received control may augment evidence, never replace the original scheduled grant operands.');
grant=bound;
serving=sixgr.util.structGet(grant,'ServingCell',NaN);
assert(upper(string(grant.Direction))=="UL" && grant.UEIndex==ue && ...
    isnumeric(serving) && isscalar(serving) && isfinite(serving) && ...
    serving==fix(serving) && serving>=1 && serving==c.ServingCell && ...
    c.ServingCell==state.CurrentServingIdx(ue) && ...
    grant.RNTI==sixgr.truth.CoupledRadioIdentity.resolve(state,ue,c.ServingCell), ...
    'sixgr:truth:ReceivedULPreparationIdentityMismatch', ...
    'Received control must belong to the current UE, RNTI and serving cell.');
assignment=control.ReceivedAssignment;
p=c.Prepared;
assert(isstruct(p) && isscalar(p) && all(isfield(p, ...
    {'ReceiverConfig','RuntimeStartSample','MinimumReceiveSamples','SampleRateHz'})), ...
    'sixgr:truth:ReceivedULPreparationContextRequired','Retain the original receiver configuration.');
sixgr.phy.pdcch.validateConnectedAssignment(p.ReceiverConfig,assignment);
controlSlot=sixgr.truth.resolvePDCCHControlSlot(grant,c.Slot);
dataSlot=sixgr.truth.runtimeULGrantSlot(grant);
assert(assignment.Direction=="UL" && assignment.RNTI==grant.RNTI && ...
    assignment.ControlAbsoluteSlot==controlSlot-1 && ...
    assignment.ControlAbsoluteSlot==p.ReceiverConfig.lls6g.runtime.AbsoluteSlotIndex0 && ...
    assignment.DataAbsoluteSlot==dataSlot-1 && ...
    string(assignment.PayloadHash)==string(grant.PDCCHGrantDCIId), ...
    'sixgr:truth:ReceivedULPreparationAssignmentMismatch', ...
    'Decoded payload, installed receive clock and admitted UL allocation must agree.');
planes=item.Planes;
assert(isstruct(planes) && ~isempty(planes) && all(isfield(planes,{'ReceiverID','Observation'})), ...
    'sixgr:truth:ReceivedULPreparationCompletionRequired','Retain the completed receiver capture.');
postIndex=find(endsWith(string({planes.ReceiverID}),":post_rf"));
assert(isscalar(postIndex) && string(planes(postIndex).ReceiverID)=="ue_"+ue+"_rx:post_rf", ...
    'sixgr:truth:ReceivedULPreparationEndpointMismatch','Use this UE''s actual post-RF endpoint.');
post=planes(postIndex).Observation;
receiveFirst=sixgr.util.structGet(p,'ReceivedTimingAlignment.ReceiveStartSample',p.RuntimeStartSample);
assert(isa(post,'sixgr.phy.waveform.WaveformObservationBuffer') && post.isComplete() && ...
    post.SampleRateHz==owner.SampleRateHz && post.SampleRateHz==p.SampleRateHz && ...
    post.StartSample==receiveFirst && ...
    post.EndSampleExclusive>=receiveFirst+p.MinimumReceiveSamples && ...
    control.AvailableAtSample==post.EndSampleExclusive && ...
    control.AvailableAtSample<=owner.Events.NextSampleIndex, ...
    'sixgr:truth:ReceivedULPreparationClockMismatch', ...
    'Control must be completely available on the live receiver clock before preparation is armed.');

% Preserve the production authority: current per-UE installation and received
% TAG, evaluated for the received future data occasion, not the planner copy.
[cfg,~]=sixgr.truth.CoupledTruthRuntime.applyUserContext(c.UserCfg{ue},state,ue,'UL');
sixgr.phy.pdcch.validateConnectedAssignment(cfg,assignment);
cfg=sixgr.phy.grid.applyRuntimeCarrierTimeline(cfg,grant.Slot,grant.Frame);
carrier=sixgr.phy.grid.makeCarrier(cfg); fs=owner.SampleRateHz;
cfg=sixgr.truth.bindSharedDataOccasion(cfg,grant.Slot,grant.Frame,fs);
first=sixgr.phy.frame.slotStartSample(carrier,grant.Slot-1,fs);
stop=sixgr.phy.frame.slotStartSample(carrier,grant.Slot,fs);
timing=sixgr.link.resolveConnectedULTransmissionTiming(cfg,first/fs,fs,stop-first);
prepareAt=min(timing.TransmitStartSample,timing.ReceiveStartSample);
assert(prepareAt>=owner.Events.NextSampleIndex && prepareAt>=control.AvailableAtSample, ...
    'sixgr:truth:LateReceivedULPreparation', ...
    'Never backfill a UE contribution or gNB observation after its first sample.');
c.Grant=grant; c.PreparationConfig=cfg;

% Finish all value-state checks before mutating the shared event owner.
% Publication is of the received grant only: execution/queue/HARQ accounting
% still belongs to the later actual first-active-sample commit.
next=sixgr.truth.recordReceivedULGrant(state,grant);
pending=sixgr.util.structGet(next,'SharedPendingULGrants',repmat(struct(),0,1));
next.SharedPendingULGrants=localAppend(pending,grant);
owner.queueULDataPreparation(ue,prepareAt,c);
state=next;
end

function tf=localTrue(value)
tf=(isnumeric(value)||islogical(value)) && isscalar(value) && isequal(double(value),1);
end

function pending=localAppend(pending,grant)
% Same heterogeneous-struct calendar semantics as the production runner.
if ~(isstruct(pending) && ~isempty(pending)), pending=grant; return; end
names=union(string(fieldnames(pending)),string(fieldnames(grant)),"stable");
for name=reshape(names,1,[])
    field=char(name);
    if ~isfield(pending,field), [pending.(field)]=deal([]); end
    if ~isfield(grant,field), grant.(field)=[]; end
end
pending=vertcat(pending,grant);
end
