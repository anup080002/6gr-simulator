function [T,diagnosticContext]=exportSharedChannelObservation(root,T,planes,prepared,planeID)
% Publish actually executed coefficients after reception, never a receiver H.
% Cropped-array, processor-waveform, manifest and file hashes are distinct.
arguments
    root {mustBeTextScalar}
    T table
    planes struct
    prepared
    planeID {mustBeTextScalar}
end
assert(istable(T) && height(T)==1 && isfolder(root), ...
    'sixgr:truth:ChannelCaptureExportScope','One completed trial and an existing run folder are required.');
[observation,evidence,captures]=sixgr.truth.sharedLinkScoringObservation(planes,prepared,planeID);
assert(evidence.ChannelReferenceCoverageComplete && ~isempty(captures), ...
    'sixgr:truth:MissingSharedChannelCapture','Do not export a channel observation without actual captured coefficients.');
selected=planes(string({planes.ReceiverID})==string(planeID));
rows=struct([]);
replays=cell(numel(captures),1);
arrayHash=@sixgr.channel.ChannelFactory.runtimeNumericArraySHA256;
for k=1:numel(captures)
    capture=captures{k}; r=capture.Reference;
    segment=selected.Segments{find(cellfun(@(s) ...
        s.Execution.StartSample==r.ExecutionStartSample && ...
        s.Execution.EndSampleExclusive==r.ExecutionEndSampleExclusive,selected.Segments),1)};
    links=segment.Execution.Links;
    link=links(string({links.ID})==capture.LinkID & ...
        string({links.TX})==capture.TX & string({links.RX})==capture.RX);
    assert(isscalar(link),'sixgr:truth:ChannelCaptureLinkMismatch','Exactly one executed physical link must own each capture.');
    replay=link.Replay;
    replays{k}=replay;
    nt=r.NumTransmitAntennas; nr=r.NumReceiveAntennas; ns=r.EndSampleExclusive-r.StartSample;
    assert(r.SampleRateHz==observation.SampleRateHz && ...
        size(r.PathGains,3)==nt && size(r.PathGains,4)==nr && ...
        size(r.PathGains,1)==ns && numel(r.SampleTimes_s)==ns && ...
        size(r.PathFilters,2)==size(r.PathGains,2) && ...
        all(isfinite(r.PathGains),'all') && all(isfinite(r.PathFilters),'all') && ...
        all(isfinite(r.SampleTimes_s),'all') && ...
        r.StateKey==string(replay.RuntimeChannelStateKey), ...
        'sixgr:truth:InvalidSharedChannelCaptureArrays','Captured times, filters and antenna dimensions must describe the actual link.');
    row=struct('SegmentIndex',k,'StartSample',r.StartSample, ...
        'EndSampleExclusive',r.EndSampleExclusive, ...
        'ExecutionStartSample',r.ExecutionStartSample, ...
        'ExecutionEndSampleExclusive',r.ExecutionEndSampleExclusive, ...
        'NumTransmitAntennas',nt,'NumReceiveAntennas',nr, ...
        'PathGainElementCount',numel(r.PathGains), ...
        'PathGainDimensions',string(jsonencode([ns size(r.PathGains,2) nt nr])), ...
        'PathGainsSHA256',string(arrayHash(r.PathGains)), ...
        'PathFiltersSHA256',string(arrayHash(r.PathFilters)), ...
        'SampleTimeCount',numel(r.SampleTimes_s), ...
        'SampleTimesSHA256',string(arrayHash(r.SampleTimes_s)), ...
        'NormalizePathGains',logical(r.NormalizePathGains), ...
        'NormalizeChannelOutputs',logical(r.NormalizeChannelOutputs));
    % These hashes and geometry describe the full processor segment, not
    % the cropped observation arrays above. Preserve their original scope.
    fields=["ChannelRealizationId","ChannelModelApplied","ChannelFadingObjectClass", ...
        "RuntimeChannelLinkKey","RuntimeChannelStateKey","RuntimeChannelSeed", ...
        "RuntimeChannelStartSample","RuntimeChannelEndSample", ...
        "RuntimeChannelCanonicalInputSamples","RuntimeChannelObjectClockExact", ...
        "RuntimeChannelInputWaveformSHA256","RuntimeChannelOutputWaveformSHA256", ...
        "RuntimeChannelReciprocityExact","RuntimeChannelReciprocityDirection", ...
        "RuntimeChannelReciprocitySource","RuntimeChannelReciprocityApproximationMode", ...
        "RuntimeChannelTransmitAndReceiveSwapped","RuntimeChannelResetCount", ...
        "RuntimeChannelPathDelays_s","RuntimeChannelAngleEvidenceAvailable", ...
        "RuntimeChannelAnglesAoD_deg","RuntimeChannelAnglesAoA_deg", ...
        "RuntimeChannelAnglesZoD_deg","RuntimeChannelAnglesZoA_deg", ...
        "RuntimeChannelAngleCoordinateFrame","RuntimeChannelAngleEvidenceSource"];
    assert(all(isfield(replay,cellstr(fields))), ...
        'sixgr:truth:MissingChannelCaptureExecution', ...
        'Do not backfill missing executed channel metadata from configuration: %s.', ...
        strjoin(fields(~isfield(replay,cellstr(fields))),', '));
    assert(replay.RuntimeChannelStartSample==r.ExecutionStartSample && ...
        replay.RuntimeChannelEndSample==r.ExecutionEndSampleExclusive, ...
        'sixgr:truth:ChannelCaptureExecutionClock','Processor hashes must identify the actual coefficient-producing execution.');
    for field=fields
        value=replay.(field);
        if endsWith(field,["_s","_deg"]) && isnumeric(value)
            row.(field+"JSON")=string(jsonencode(value));
        else
            % Empty char arrays become zero-width table variables and can
            % disappear from CSV (notably FDD reciprocity metadata).
            if ischar(value), value=string(value); end
            row.(field)=value;
        end
    end
    if isempty(rows), rows=row; else, rows(k)=row; end %#ok<AGROW>
end
diagnosticContext=localDiagnosticContext(observation,evidence,captures,replays,arrayHash);
manifest=struct('Contract',"actual_shared_channel_observation/v1", ...
    'Representation',"sample_indexed_path_gains_and_filters_not_resource_grid_H", ...
    'Source',"same_executed_NR_channel_path_gains_and_filters", ...
    'LinkID',evidence.LinkID,'TransmitterID',evidence.TransmitterID, ...
    'ReceiverID',evidence.ReceiverID,'SampleRateHz',observation.SampleRateHz, ...
    'ObservationStartSample',observation.StartSample, ...
    'ObservationEndSampleExclusive',observation.EndSampleExclusive, ...
    'InactiveIntervals',evidence.ChannelReferenceInactiveIntervals, ...
    'ReceiverEstimatorInput',false,'AdditionalChannelExecutions',0, ...
    'RFIncluded',false,'LargeScaleLossApplied',false,'Segments',rows);
manifestJSON=string(jsonencode(manifest));
manifestHash=sixgr.phy.waveform.WaveformHash.bytes(manifestJSON);
token="channel_observation_"+manifestHash;
matRelative="channel/mat/"+token+".mat";
csvRelative="channel/csv/"+token+"_segments.csv";
matPath=fullfile(root,matRelative); csvPath=fullfile(root,csvRelative);
reuse=isfile(matPath) || isfile(csvPath);
assert(~reuse || (isfile(matPath) && isfile(csvPath)), ...
    'sixgr:truth:PartialChannelCapturePublication', ...
    'An incomplete prior publication must not be overwritten or silently repaired.');
if ~reuse
sixgr.util.matSave(matPath,struct('ManifestJSON',manifestJSON,'Captures',{captures}), ...
    'UseArtifactStore',false);
segmentT=struct2table(rows,'AsArray',true);
segmentT.ChannelObservationID=repmat("chobs_"+manifestHash,height(segmentT),1);
segmentT.ObservationStartSample=repmat(observation.StartSample,height(segmentT),1);
segmentT.ObservationEndSampleExclusive=repmat(observation.EndSampleExclusive,height(segmentT),1);
segmentT.CoefficientMATFile=repmat(matRelative,height(segmentT),1);
segmentT.Source=repmat(manifest.Source,height(segmentT),1);
sixgr.util.csvWriteTable(csvPath,segmentT,'PreserveSchema',true);
end
T.ChannelObservationID="chobs_"+manifestHash;
T.ChannelObservationManifestJSON=manifestJSON;
T.ChannelObservationManifestSHA256=manifestHash;
T.ChannelObservationMATFile=matRelative;
T.ChannelObservationMATFileSHA256=sixgr.phy.waveform.WaveformHash.file(matPath);
T.ChannelObservationSegmentsCSV=csvRelative;
T.ChannelObservationSegmentsCSVSHA256=sixgr.phy.waveform.WaveformHash.file(csvPath);
T.ChannelObservationSegmentCount=numel(captures);
T.ChannelObservationStartSample=observation.StartSample;
T.ChannelObservationEndSampleExclusive=observation.EndSampleExclusive;
T.ChannelObservationSampleRateHz=observation.SampleRateHz;
T.ChannelObservationSource=manifest.Source;
T.ChannelObservationReceiverEstimatorInput=false;
% These fields describe the cropped coefficients that actually acted on
% this receive window.  They are attached only after practical decoding;
% the receiver never receives these arrays as an estimator input.
T.RuntimeChannelStartSample=diagnosticContext.RuntimeChannelStartSample;
T.RuntimeChannelEndSample=diagnosticContext.RuntimeChannelEndSample;
T.RuntimeChannelCanonicalInputSamples=diagnosticContext.RuntimeChannelCanonicalInputSamples;
T.RuntimeChannelCaptureScope=diagnosticContext.RuntimeChannelCaptureScope;
T.RuntimeChannelObjectClockExact=diagnosticContext.RuntimeChannelObjectClockExact;
T.RuntimeChannelLinkKey=diagnosticContext.RuntimeChannelLinkKey;
T.RuntimeChannelStateKey=diagnosticContext.RuntimeChannelStateKey;
T.RuntimeChannelSeed=diagnosticContext.RuntimeChannelSeed;
T.RuntimeChannelReciprocityExact=diagnosticContext.RuntimeChannelReciprocityExact;
T.RuntimeChannelReciprocityDirection=diagnosticContext.RuntimeChannelReciprocityDirection;
T.RuntimeChannelReciprocitySource=diagnosticContext.RuntimeChannelReciprocitySource;
T.RuntimeChannelReciprocityApproximationMode=diagnosticContext.RuntimeChannelReciprocityApproximationMode;
T.RuntimeChannelTransmitAndReceiveSwapped=diagnosticContext.RuntimeChannelTransmitAndReceiveSwapped;
T.RuntimeChannelPathGainsSHA256=diagnosticContext.RuntimeChannelPathGainsSHA256;
T.RuntimeChannelPathGainElementCount=numel(diagnosticContext.RuntimeChannelPathGains);
T.RuntimeChannelPathGainDimensions=string(jsonencode(size(diagnosticContext.RuntimeChannelPathGains)));
if reuse
    % SRS and PUSCH may observe exactly the same executed link interval.
    % Reuse immutable files only after independently checking their saved
    % arrays/CSV against the manifest computed from THIS actual capture.
    % Rehashing a corrupted file alone is not evidence of valid content.
    sixgr.channel.validateSharedChannelObservationArtifact(root,T);
end
end

function context=localDiagnosticContext(observation,evidence,captures,replays,arrayHash)
assert(~isempty(captures) && numel(captures)==numel(replays), ...
    'sixgr:truth:MissingChannelDiagnosticCapture', ...
    'Post-decode channel diagnostics require every actual capture and replay record.');
refs=cellfun(@(c)c.Reference,captures,'UniformOutput',false);
bounds=cell2mat(cellfun(@(r)[r.StartSample r.EndSampleExclusive],refs,'UniformOutput',false));
% Receive windows can include an explicitly inactive TDD prefix or tail.
% Keep that whole observation in the manifest/waveform, but never invent
% channel coefficients for a direction that was not executed. The scalar
% diagnostic clock still requires one contiguous ACTIVE coefficient span.
inactive=evidence.ChannelReferenceInactiveIntervals;
coverage=sortrows([bounds;inactive],1);
assert(isequal(bounds,evidence.ChannelReferenceIntervals) && ...
    coverage(1,1)==observation.StartSample && ...
    coverage(end,2)==observation.EndSampleExclusive && ...
    all(coverage(:,2)>coverage(:,1)) && ...
    all(coverage(2:end,1)==coverage(1:end-1,2)) && ...
    all(bounds(2:end,1)==bounds(1:end-1,2)), ...
    'sixgr:truth:NonContiguousChannelDiagnosticCapture', ...
    'Actual active coefficients must be contiguous, with full active/inactive observation coverage.');
firstRef=refs{1}; firstReplay=replays{1};
pathDelays=double(firstReplay.RuntimeChannelPathDelays_s(:));
assert(~isempty(pathDelays) && numel(pathDelays)==size(firstRef.PathGains,2), ...
    'sixgr:truth:InvalidChannelDiagnosticPathAxis', ...
    'Executed path delays must index the captured path-gain tensor.');
for k=1:numel(refs)
    r=refs{k}; replay=replays{k};
    assert(size(r.PathGains,2)==numel(pathDelays) && ...
        isequaln(double(replay.RuntimeChannelPathDelays_s(:)),pathDelays) && ...
        string(replay.RuntimeChannelStateKey)==string(firstReplay.RuntimeChannelStateKey) && ...
        string(replay.RuntimeChannelLinkKey)==string(firstReplay.RuntimeChannelLinkKey) && ...
        double(replay.RuntimeChannelSeed)==double(firstReplay.RuntimeChannelSeed), ...
        'sixgr:truth:InconsistentChannelDiagnosticSegments', ...
        'One receive observation must retain one path axis and one runtime fading state.');
end
gainCells=cellfun(@(r)r.PathGains,refs,'UniformOutput',false);
timeCells=cellfun(@(r)double(r.SampleTimes_s(:)),refs,'UniformOutput',false);
pathGains=cat(1,gainCells{:});
sampleTimes=vertcat(timeCells{:});
assert(size(pathGains,1)==bounds(end,2)-bounds(1,1) && ...
    numel(sampleTimes)==size(pathGains,1) && all(diff(sampleTimes)>0), ...
    'sixgr:truth:InvalidChannelDiagnosticClock', ...
    'Captured path gains must have one strictly ordered time sample per direction-active waveform sample.');
postChannelWaveform=observation.readComplete();
assert(size(postChannelWaveform,1)==observation.EndSampleExclusive-observation.StartSample && ...
    ~isempty(postChannelWaveform) && all(isfinite(postChannelWaveform),'all'), ...
    'sixgr:truth:InvalidPostChannelDiagnosticWaveform', ...
    'Post-channel evidence must be the complete finite desired-link scoring waveform on the observed clock.');
for k=1:size(inactive,1)
    first=inactive(k,1)-observation.StartSample+1;
    last=inactive(k,2)-observation.StartSample;
    assert(all(postChannelWaveform(first:last,:)==0,'all'), ...
        'sixgr:truth:InactiveChannelDiagnosticNonzeroContribution', ...
        'An excluded direction-inactive interval must contain actual zero desired-link scoring samples.');
end
context=struct( ...
    'PostChannelWaveform',postChannelWaveform, ...
    'PostChannelWaveformSHA256',string(arrayHash(postChannelWaveform)), ...
    'PostChannelWaveformSource','actual_desired_link_after_tx_rf_channel_and_large_scale_loss_before_sum_noise_and_rx_rf', ...
    'RuntimeChannelPathGains',pathGains, ...
    'RuntimeChannelPathGainSampleTimes_s',sampleTimes, ...
    'RuntimeChannelDiagnosticMaxTimeSamples',128, ...
    'RuntimeChannelPathDelays_s',reshape(pathDelays,1,[]), ...
    'RuntimeChannelPathGainsSHA256',string(arrayHash(pathGains)), ...
    'RuntimeChannelStartSample',double(bounds(1,1)), ...
    'RuntimeChannelEndSample',double(bounds(end,2)), ...
    'RuntimeChannelCanonicalInputSamples',double(size(pathGains,1)), ...
    'RuntimeChannelCaptureScope',"actual_contiguous_direction_active_interval_within_receive_window", ...
    'RuntimeChannelObjectClockExact',all(cellfun(@(r)logical(r.RuntimeChannelObjectClockExact),replays)), ...
    'RuntimeChannelLinkKey',string(firstReplay.RuntimeChannelLinkKey), ...
    'RuntimeChannelStateKey',string(firstReplay.RuntimeChannelStateKey), ...
    'RuntimeChannelSeed',double(firstReplay.RuntimeChannelSeed), ...
    'RuntimeChannelReciprocityExact',logical(firstReplay.RuntimeChannelReciprocityExact), ...
    'RuntimeChannelReciprocityDirection',string(firstReplay.RuntimeChannelReciprocityDirection), ...
    'RuntimeChannelReciprocitySource',string(firstReplay.RuntimeChannelReciprocitySource), ...
    'RuntimeChannelReciprocityApproximationMode',string(firstReplay.RuntimeChannelReciprocityApproximationMode), ...
    'RuntimeChannelTransmitAndReceiveSwapped',logical(firstReplay.RuntimeChannelTransmitAndReceiveSwapped), ...
    'RuntimeChannelAngleEvidenceAvailable',logical(firstReplay.RuntimeChannelAngleEvidenceAvailable), ...
    'RuntimeChannelAnglesAoD_deg',double(firstReplay.RuntimeChannelAnglesAoD_deg), ...
    'RuntimeChannelAnglesAoA_deg',double(firstReplay.RuntimeChannelAnglesAoA_deg), ...
    'RuntimeChannelAnglesZoD_deg',double(firstReplay.RuntimeChannelAnglesZoD_deg), ...
    'RuntimeChannelAnglesZoA_deg',double(firstReplay.RuntimeChannelAnglesZoA_deg), ...
    'RuntimeChannelAngleCoordinateFrame',string(firstReplay.RuntimeChannelAngleCoordinateFrame), ...
    'RuntimeChannelAngleEvidenceSource',string(firstReplay.RuntimeChannelAngleEvidenceSource));
assert(context.RuntimeChannelObjectClockExact, ...
    'sixgr:truth:InexactChannelDiagnosticClock', ...
    'Do not publish an exact shared-channel diagnostic from an inexact runtime object clock.');
end
