function row = connectedDCIAssignmentEvidence(assignment)
% Scalar CSV contract. Empty input means no accepted observation.
row=struct('DecodedDCIAssignmentAvailable',false, ...
    'DecodedDCIAssignmentDigest',"",'DecodedDCIContextDigest',"", ...
    'DecodedDCIConfigurationEpoch',NaN,'DecodedDCIFormat',"", ...
    'DecodedDCIControlAbsoluteSlot',NaN,'DecodedDCIDataAbsoluteSlot',NaN, ...
    'DecodedDCITimeDomainAssignmentIndex',NaN, ...
    'DecodedDCINumLayers',NaN,'DecodedDCIDMRSPortSet',"",'DecodedDCIDMRSPortIndexDomain',"", ...
    'DecodedDCINumCDMGroupsWithoutData',NaN,'DecodedDCIDMRSFrontLoadSymbols',NaN, ...
    'DecodedDCINSCID',NaN,'DecodedDCIAntennaPortCodepoint',NaN, ...
    'DecodedDCITPMI',NaN,'DecodedDCISRSResourceIndex',NaN, ...
    'DecodedDCISRSResourceSelectionSource',"",'DecodedDCIK1Slots',NaN, ...
    'DecodedDCIHARQFeedbackAbsoluteSlot',NaN, ...
    'DecodedDCIPUCCHResourceIndicator',NaN,'DecodedDCITCICodepoint',NaN,'DecodedDCISource',"");
if isempty(fieldnames(assignment)), return; end
row.DecodedDCIAssignmentAvailable=true;
row.DecodedDCIAssignmentDigest=assignment.AssignmentDigest;
row.DecodedDCIDMRSPortSet=string(jsonencode(assignment.DMRSPortSet));
pairs={'ContextDigest','ContextDigest';'ConfigurationEpoch','ConfigurationEpoch'; ...
    'Format','DCIFormat';'ControlAbsoluteSlot','ControlAbsoluteSlot'; ...
    'DataAbsoluteSlot','DataAbsoluteSlot';'TimeDomainAssignmentIndex','TimeDomainAssignmentIndex'; ...
    'NumLayers','NumLayers';'DMRSPortIndexDomain','DMRSPortIndexDomain'; ...
    'NumCDMGroupsWithoutData','NumCDMGroupsWithoutData'; ...
    'DMRSFrontLoadSymbols','DMRSFrontLoadSymbols';'NSCID','NSCID'; ...
    'AntennaPortCodepoint','AntennaPortCodepoint';'TPMI','TPMI'; ...
    'SRSResourceIndex','SRSResourceIndex';'SRSResourceSelectionSource','SRSResourceSelectionSource'; ...
    'K1Slots','K1Slots';'HARQFeedbackAbsoluteSlot','HARQFeedbackAbsoluteSlot'; ...
    'PUCCHResourceIndicator','PUCCHResourceIndicator';'TCICodepoint','TCICodepoint';'Source','Source'};
for k=1:size(pairs,1)
    if isfield(assignment,pairs{k,2})
        row.(['DecodedDCI' pairs{k,1}])=assignment.(pairs{k,2});
    end
end
end
