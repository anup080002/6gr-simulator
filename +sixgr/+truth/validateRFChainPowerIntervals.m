function complete=validateRFChainPowerIntervals(T,intervals)
% Validate saved measurements against actual RF execution, not configuration.
complete=false;
if isempty(T), return; end
prototype=sixgr.truth.rfChainPowerInterval();
assert(istable(T)&&all(ismember(prototype.Properties.VariableNames,T.Properties.VariableNames)), ...
    'sixgr:truth:RFChainPowerEvidence','Missing per-chain measurement columns.');
keys=string(T.Role)+"|"+string(T.EndpointID)+"|"+string(T.StartSample);
assert(numel(unique(keys))==height(T),'sixgr:truth:RFChainPowerEvidence','Duplicate chain-power intervals.');
for k=1:height(T)
    r=T(k,:); n=r.PhysicalChainCount;
    base=intervals(intervals.Role==r.Role & intervals.EndpointID==r.EndpointID & ...
        intervals.StartSample==r.StartSample,:);
    assert(height(base)==1 && r.Direction==base.Direction && r.EndSampleExclusive==base.EndSampleExclusive && ...
        r.SampleRateHz==base.SampleRateHz && r.SampleCount==base.SampleCount && ...
        n==base.PhysicalPortCount, ...
        'sixgr:truth:RFChainPowerEvidence','Chain measurements must match one committed RF interval.');
    assert(r.Source=="measured_physical_chain_sample_power" && ...
        r.ReferencePlane=="RF_operator_boundaries_not_TRP_or_directional_EIRP" && ...
        r.Population=="all_samples_including_cp_and_idle_not_active_RE_EPRE", ...
        'sixgr:truth:RFChainPowerEvidence','Do not relabel RF sample power as RE power or TRP.');
    assert(ismember(r.WaveformAmplitudeUnit,["undeclared","sqrt_mW","normalized_complex_baseband"]), ...
        'sixgr:truth:RFChainPowerUnit','Invalid amplitude reference.');
    for stage=["Input","Output","PostPA"]
        if stage=="PostPA" && r.Role=="RX"
            assert(r.PostPAPerChainMeanSquareJSON=="" && isnan(r.PostPATotalMeanSquare) && ...
                isnan(r.PostPATotalPower_mW) && r.PostPAPerChainPower_dBmJSON=="" && ...
                r.PostPAStatus=="not_applicable_receiver", ...
                'sixgr:truth:RFChainPowerPlane','RX cannot contain TX PA measurements.');
            continue;
        end
        p=jsondecode(char(r.(stage+"PerChainMeanSquareJSON"))); p=double(p(:));
        total=r.(stage+"TotalMeanSquare");
        assert(numel(p)==n && isreal(p) && all(isfinite(p)&p>=0) && ...
            isfinite(total)&&total>=0 && abs(sum(p)-total)<=max(1e-11*total,64*eps(total)), ...
            'sixgr:truth:RFChainPowerClosure','Per-chain power must close to endpoint total.');
        if stage~="PostPA"
            expected=base.(stage+"MeanSquare")*n;
            assert(abs(expected-total)<=max(1e-10*expected,64*eps(expected)), ...
                'sixgr:truth:RFChainPowerClosure','Per-chain power disagrees with RF operator measurement.');
        else
            assert(r.PostPAStatus=="measured_after_PA_stage_including_disabled_identity", ...
                'sixgr:truth:RFChainPowerPlane','Retain the actual post-PA plane.');
            if r.WaveformAmplitudeUnit=="sqrt_mW"
                d=double(jsondecode(char(r.PostPAPerChainPower_dBmJSON))); d=d(:);
                assert(r.PostPATotalPower_mW==total && numel(d)==n && ...
                    all(isfinite(d(p>0))) && all(abs(d(p>0)-10*log10(p(p>0)))<1e-10) && ...
                    all(isnan(d(p==0))|d(p==0)==-Inf), ...
                    'sixgr:truth:RFChainPowerUnit','Absolute chain powers require the retained sqrt(mW) plane.');
            else
                assert(isnan(r.PostPATotalPower_mW)&&r.PostPAPerChainPower_dBmJSON=="", ...
                    'sixgr:truth:RFChainPowerUnit','Normalized samples cannot be published as mW/dBm.');
            end
        end
    end
end
complete=height(T)==height(intervals)&&~isempty(intervals);
end
