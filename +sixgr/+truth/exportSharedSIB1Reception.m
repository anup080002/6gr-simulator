function path=exportSharedSIB1Reception(state,runFolder)
%EXPORTSHAREDSIB1RECEPTION Publish original delivered SI-only observations.
% This is a serialization/consistency boundary, not independent execution
% authentication. SIB1ResultDelivery owns capture/receiver/generation proof.
% No received MIB, transmitted SI, or block trial is invented here.
arguments
    state (1,1) struct
    runFolder (1,1) string
end
path="";
if ~isfield(state,'SharedSIB1ReceptionTable'), return; end
T=state.SharedSIB1ReceptionTable;
assert(istable(T),'sixgr:truth:SIB1ExportSchema','Original SI reception evidence must be a table.');
if height(T)==0, return; end
text=["ObservationID","ReceivedMIBGenerationID","RawPostRFInputSHA256", ...
    "DecoderInputSHA256","RecoverySHA256","DeliveryStatus","Status", ...
    "FailureReason","FailureIdentifier","SIB1InputSampleSHA256", ...
    "SIB1PayloadHashRx","SIB1RxTreeHash","PriorBCHContextSHA256"];
coordinates=["UEId","ServingCell","ResourceAbsoluteSlot0Based","DeliverySlot1Based", ...
    "ObservationStartSample","ObservationEndSampleExclusive","ObservationSampleRateHz"];
flags=["Crash","SIB1ReceptionAttempted","SIB1ObservationComplete","DCICrcPass", ...
    "DLSCHCrcPass","SIB1ASN1DecodeOk","SIB1SemanticValid","StrictOk","NewBCHReceptionAttempted"];
assert(all(ismember([text,coordinates,flags,"Installed"],string(T.Properties.VariableNames))), ...
    'sixgr:truth:SIB1ExportSchema','Preserve the complete original SIB1ResultDelivery schema.');
assert(~any(ismember(["BCHCrcPass","BCHCRCValid","MIBDecoded","PBCHStrictReceiverEvidenceOk", ...
    "SS_RSRP_dBm","SS_RSRQ_dB","SS_SINR_dB"],string(T.Properties.VariableNames))), ...
    'sixgr:truth:SIB1ExportScope','SI-only reception cannot manufacture new PBCH or SSB measurements.');
for name=text
    v=T.(name);
    assert(isstring(v) && isequal(size(v),[height(T),1]) && ~any(ismissing(v)), ...
        'sixgr:truth:SIB1ExportOperands','Preserve original scalar text in %s.',name);
end
for name=["ObservationID","ReceivedMIBGenerationID","DeliveryStatus","Status"]
    assert(all(strlength(T.(name))>0),'sixgr:truth:SIB1ExportIdentity','Missing original %s.',name);
end
for name=coordinates
    v=T.(name);
    assert(isnumeric(v) && isreal(v) && isequal(size(v),[height(T),1]) && ...
        all(isfinite(v) & v>=0 & v<flintmax), ...
        'sixgr:truth:SIB1ExportOperands','Invalid original coordinate %s.',name);
    if name~="ObservationSampleRateHz"
        assert(all(v==fix(v)),'sixgr:truth:SIB1ExportOperands','Require integer original coordinate %s.',name);
    end
end
assert(all(T.UEId>=1 & T.ServingCell>=1 & T.DeliverySlot1Based>=1 & ...
    T.ObservationSampleRateHz>0 & T.ObservationEndSampleExclusive>T.ObservationStartSample), ...
    'sixgr:truth:SIB1ExportOperands','Invalid original receiver or capture extent.');
for name=flags
    v=T.(name);
    assert(isnumeric(v) && isreal(v) && isequal(size(v),[height(T),1]) && ...
        all(isnan(v)|v==0|v==1),'sixgr:truth:SIB1ExportOperands', ...
        'Retain original numeric 0/1/unavailable outcome %s.',name);
end
assert(islogical(T.Installed) && isequal(size(T.Installed),[height(T),1]), ...
    'sixgr:truth:SIB1ExportOperands','Installation is an original logical owner decision.');
assert(all(T.NewBCHReceptionAttempted==0),'sixgr:truth:SIB1ExportScope', ...
    'A later SI result must explicitly retain no new BCH reception.');
assert(numel(unique(T.ObservationID))==height(T) && ...
    isfield(state,'CompletedSIB1ObservationIDs') && isstring(state.CompletedSIB1ObservationIDs) && ...
    isvector(state.CompletedSIB1ObservationIDs) && ~any(ismissing(state.CompletedSIB1ObservationIDs)) && ...
    all(ismember(T.ObservationID,state.CompletedSIB1ObservationIDs)), ...
    'sixgr:truth:SIB1ExportIdentity','Every delivered row needs its original completed observation identity.');
assert(isfield(state,'CfgMobility') && isstruct(state.CfgMobility) && isscalar(state.CfgMobility) && ...
    isfield(state,'SharedWaveformStream'), ...
    'sixgr:truth:SIB1ExportClock','Retain the original carrier configuration and waveform sample clock.');
owner=state.SharedWaveformStream; fs=owner.SampleRateHz;
assert(isnumeric(fs) && isreal(fs) && isscalar(fs) && isfinite(fs) && fs>0 && ...
    all(T.ObservationSampleRateHz==fs), ...
    'sixgr:truth:SIB1ExportClock','SI captures must retain the original waveform-owner sample rate.');
carrier=sixgr.phy.grid.makeCarrier(state.CfgMobility);
for slot=reshape(unique(T.DeliverySlot1Based),1,[])
    boundary=sixgr.phy.frame.slotStartSample(carrier,slot-1,fs);
    assert(all(T.ObservationEndSampleExclusive(T.DeliverySlot1Based==slot)<=boundary) && ...
        boundary<=owner.Events.NextSampleIndex, ...
        'sixgr:truth:SIB1ExportClock','Delivery must follow actual capture completion on the canonical sample clock.');
end
for name=["RawPostRFInputSHA256","DecoderInputSHA256","RecoverySHA256","PriorBCHContextSHA256"]
    localHashes(T.(name),false);
end
for name=["SIB1InputSampleSHA256","SIB1PayloadHashRx","SIB1RxTreeHash"]
    localHashes(T.(name),true);
end
% Preserve failures and unavailable flags as recorded. Only reject positive
% claims that contradict the original earlier-stage/attempt operands.
positive=T.DCICrcPass==1 | T.DLSCHCrcPass==1 | T.SIB1ASN1DecodeOk==1 | ...
    T.SIB1SemanticValid==1 | T.StrictOk==1;
assert(all(~positive | (T.SIB1ReceptionAttempted==1 & T.SIB1ObservationComplete==1)), ...
    'sixgr:truth:SIB1ExportOutcome','A successful stage requires an original complete SI attempt.');
assert(all(T.DLSCHCrcPass~=1 | T.DCICrcPass==1) && ...
    all(T.SIB1ASN1DecodeOk~=1 | T.DLSCHCrcPass==1) && ...
    all(T.SIB1SemanticValid~=1 | T.SIB1ASN1DecodeOk==1), ...
    'sixgr:truth:SIB1ExportOutcome','Preserve causal original SI decode stages.');
accepted=T.StrictOk==1;
assert(all(~accepted | (T.Crash==0 & T.DCICrcPass==1 & T.DLSCHCrcPass==1 & ...
    T.SIB1ASN1DecodeOk==1 & T.SIB1SemanticValid==1 & ...
    strlength(T.SIB1InputSampleSHA256)>0 & strlength(T.SIB1PayloadHashRx)>0 & ...
    strlength(T.SIB1RxTreeHash)>0)) && all(~T.Installed | accepted) && ...
    all(T.Installed==(T.DeliveryStatus=="installed_original_received_SIB1")), ...
    'sixgr:truth:SIB1ExportOutcome','Installation requires the original accepted SI result, not file presence.');
if ~sixgr.util.persistenceEnabled(), return; end
layout=sixgr.report.resultLayout(runFolder);
path=string(fullfile(layout.AirInterfaceCSVDir,'sib1_received_trials.csv'));
sixgr.util.csvWriteTable(path,T,'PreserveSchema',true,'RoundTripNumericText',true);
end

function localHashes(values,allowEmpty)
valid=~cellfun('isempty',regexp(cellstr(values),'^[0-9a-fA-F]{64}$','once'));
if allowEmpty, valid=valid | strlength(values)==0; end
assert(all(valid),'sixgr:truth:SIB1ExportIdentity','Preserve original SHA256 tokens; no replacement hashes.');
end
