function e=measureDataCarrierGridPower(grid,nfft,symbols,cfg)
% Energy of actual received REs; the frozen operating mode owns the units.
validateattributes(grid,{'single','double'},{'nonempty','finite'});
validateattributes(nfft,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(symbols,{'numeric'},{'vector','nonempty','real','finite','integer','nonnegative'});
assert(ndims(grid)<=3 && nfft>=size(grid,1) && ...
    all(symbols<size(grid,2)) && numel(unique(symbols))==numel(symbols), ...
    'sixgr:truth:InvalidCarrierPowerGrid','Require actual distinct received grid symbols and FFT dimensions.');
normalized=strcmpi(string(sixgr.util.structGet(cfg,'integration.run_mode','')),'FIXED_SNR_SWEEP') && ...
    logical(sixgr.util.structGet(cfg,'integration.configured_snr_is_link_authority',false));
if normalized
    measured=double(grid);
else
    measured=double(grid)/(double(nfft)*sqrt(1000));
end
power=reshape(sum(abs(measured(:,symbols+1,:)).^2,1),numel(symbols),size(grid,3));
branch=mean(power,1);
assert(all(isfinite(power(:))) && all(branch>0),'sixgr:truth:UnavailablePhysicalCarrierPower', ...
    'Do not fill unavailable or zero-energy receive branches with finite power.');
if normalized
    e=struct('ContractVersion',"received_data_carrier_power/v2", ...
        'PowerReferencePlane',"normalized_fixed_esn0_unit_occupied_re_es", ...
        'Source',"actual_normalized_received_IQ_OFDM_carrier_energy", ...
        'InputAmplitudeUnit',"normalized_OFDM_waveform_unit_occupied_re_es", ...
        'GridAmplitudeUnit',"sqrt_UnitOccupiedRE_Es", ...
        'SymbolPowerPerAntenna_UnitOccupiedRE_Es',power, ...
        'RSSIPerAntenna_dB_re_UnitOccupiedRE_Es',10*log10(branch));
else
    e=struct('ContractVersion',"received_data_carrier_power/v1", ...
        'PowerReferencePlane',"receiver_antenna_connector_pre_composite_front_end", ...
        'Source',"actual_physical_received_IQ_OFDM_carrier_energy", ...
        'InputAmplitudeUnit',"sqrt_mW",'GridAmplitudeUnit',"sqrt_W", ...
        'SymbolPowerPerAntenna_W',power,'RSSIPerAntenna_dBm',10*log10(branch)+30);
end
end
