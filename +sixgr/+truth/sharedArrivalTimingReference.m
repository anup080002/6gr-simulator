function ref=sharedArrivalTimingReference(planes,transmitStartSample)
% Post-reception scoring only. This reference must never drive acquisition.
% A peak estimator need not choose the earliest path on a fading channel.
validateattributes(transmitStartSample,{'numeric'},{'scalar','finite','integer','nonnegative'});
ids=string({planes.ReceiverID});
postIndex=find(endsWith(ids,':post_rf')); txIndex=find(endsWith(ids,':tx'));
assert(isscalar(postIndex) && isscalar(txIndex), ...
    'sixgr:truth:ArrivalTimingIdentity','One actual TX/RX pair is required.');
post=planes(postIndex).Observation;
assert(post.isComplete(),'sixgr:truth:ArrivalTimingIncomplete','Complete reception before timing scoring.');
rxID=extractBefore(ids(postIndex),':post_rf'); txID=extractBefore(ids(txIndex),':tx');
rows=zeros(0,7);
for segment=planes(postIndex).Segments(:).'
    s=segment{1}; e=s.Execution;
    link=e.Links(string({e.Links.TX})==txID & string({e.Links.RX})==rxID);
    if isempty(link), continue; end % Reciprocal opposite-direction interval.
    tx=e.TX(string({e.TX.ID})==txID); rx=e.RX(string({e.RX.ID})==rxID);
    assert(isscalar(link) && isscalar(tx) && isscalar(rx), ...
        'sixgr:truth:ArrivalTimingIdentity','Do not combine timing from another link.');
    r=link.Replay;
    required={'RuntimeChannelExpectedEarliestArrivalDelay_samples', ...
        'RuntimeChannelAppliedAlignmentTrimSamples','RuntimeChannelFilterDelay_samples'};
    assert(all(isfield(r,required)) && ...
        isfield(tx.Replay,'InjectedTimingOffset_samples') && isfield(rx.Replay,'InjectedTimingOffset_samples'), ...
        'sixgr:truth:ArrivalTimingMissingExecution','Retain actual channel and endpoint timing operators.');
    values=[s.StartSample s.EndSampleExclusive tx.Replay.InjectedTimingOffset_samples ...
        rx.Replay.InjectedTimingOffset_samples r.RuntimeChannelExpectedEarliestArrivalDelay_samples ...
        r.RuntimeChannelAppliedAlignmentTrimSamples r.RuntimeChannelFilterDelay_samples];
    assert(all(isfinite(values)),'sixgr:truth:ArrivalTimingMissingExecution','Timing operators must be finite.');
    rows(end+1,:)=values; %#ok<AGROW>
end
assert(~isempty(rows),'sixgr:truth:ArrivalTimingMissingExecution','No actual desired-link timing execution.');
operators=unique(rows(:,3:end),'rows');
assert(size(operators,1)==1,'sixgr:truth:TimeVaryingArrivalTiming', ...
    'A changing timing operator requires interval-specific scoring, not a scalar reference.');
delay=sum(operators(1:3))-operators(4);
ref=struct('Source',"executed_TX_clock_plus_RF_and_first_path_minus_channel_alignment_trim", ...
    'ReferencePlane',"earliest_path_at_receiver_capture_input_not_strongest_correlation_peak", ...
    'ReceiverEstimatorInput',false,'AdditionalChannelExecutions',0, ...
    'TransmitStartSample',double(transmitStartSample),'ReceiveStartSample',post.StartSample, ...
    'SampleRateHz',post.SampleRateHz,'TXRFDelay_samples',operators(1), ...
    'RXRFDelay_samples',operators(2),'ChannelEarliestDelay_samples',operators(3), ...
    'ChannelAlignmentTrim_samples',operators(4),'ChannelFilterDelay_samples',operators(5), ...
    'ExpectedArrivalOffset_samples',double(transmitStartSample)-post.StartSample+delay, ...
    'ExecutionIntervals',rows(:,1:2));
end
