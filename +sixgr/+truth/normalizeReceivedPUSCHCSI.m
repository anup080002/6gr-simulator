function observed=normalizeReceivedPUSCHCSI(rx,context,report)
% Decode only receiver-owned CSI fields; no TX payload, identity or lengths.
% The coordinator must additionally prove the configured occasion/capture.
assert(isstruct(rx) && isscalar(rx) && ...
    isa(context,'sixgr.phy.ul.pusch.PUSCHUCIReceiveContext') && isscalar(context), ...
    'sixgr:truth:MissingIndependentPUSCHCSIContext','Use the actual independent receiver context.');
parts={sixgr.util.structGet(rx,'DecodedCSIPart1Bits',int8([])), ...
    sixgr.util.structGet(rx,'DecodedCSIPart2Bits',int8([]))};
for k=1:2
    v=parts{k};
    assert((isnumeric(v)||islogical(v)) && isreal(v) && ...
        (isvector(v)||isempty(v)) && all(isfinite(v(:))) && all(v(:)==0|v(:)==1), ...
        'sixgr:truth:InvalidReceivedCSIBit','Validate decoded CSI bits before integer conversion.');
    parts{k}=int8(v(:));
end
if isempty(report)
    assert(strlength(context.Data.CSIReportConfigID)==0 && all(cellfun(@isempty,parts)), ...
        'sixgr:truth:UnexpectedReceivedPUSCHCSI','No configured CSI obligation may acquire decoded CSI.');
    observed=struct([]); return;
end
assert(isa(report,'sixgr.phy.mimo.CSIReportConfiguration') && isscalar(report) && ...
    report.UCIChannel=="PUSCH" && report.ReportConfigID==context.Data.CSIReportConfigID && ...
    report.Epoch==context.Data.CSIConfigurationEpoch, ...
    'sixgr:truth:PUSCHCSIReceiveContextMismatch','Bind CSI to the independently installed report schema.');
observed=struct('ReceiverContextDigest',context.Digest, ...
    'CSIReportConfigID',report.ReportConfigID,'CSIConfigurationEpoch',report.Epoch, ...
    'DecodeOk',false,'CRCPass',NaN,'DecodedPart1',parts{1},'DecodedPart2',parts{2}, ...
    'Fields',struct(),'Source',"actual_received_CSI_fields_and_installed_schema");
e=sixgr.util.structGet(rx,'UCIReceiverEvidence',struct());
assert(isstruct(e) && isscalar(e),'sixgr:truth:InvalidPUSCHCSIReceiverEvidence', ...
    'Retain structured receiver-owned CSI evidence.');
if isempty(fieldnames(e))
    % Throughput adapters retain these flags in a named envelope; the
    % receive-only path supplies the actual PUSCH_Rx result directly.
    flags=sixgr.util.structGet(rx,'IndependentUCICompletionFlags',rx);
    assert(isequal(sixgr.util.structGet(flags,'NoiseVarStrictFailure',[]),true) && ...
        isequal(sixgr.util.structGet(flags,'DecodeAttempted',[]),false) && ...
        isequal(sixgr.util.structGet(flags,'ULSCHDecodeAttempted',[]),false) && ...
        isequal(sixgr.util.structGet(flags,'ReceiverUsable',[]),false) && all(cellfun(@isempty,parts)), ...
        'sixgr:truth:MissingIndependentPUSCHCSIEvidence', ...
        'Only the explicit unattempted strict-noise failure may lack decoder evidence.');
    observed.Source="actual_receiver_strict_noise_gate_before_demapping"; return;
end
required={'ReceiverContextDigest','CSI2LengthAuthority','CSIPart1DecodedBeforePart2', ...
    'ResolvedCSI1BitCount','ResolvedCSI2BitCount','CSIPresenceResolved','CSIReportDetected'};
assert(all(isfield(e,required)) && isequal(string(e.ReceiverContextDigest),context.Digest), ...
    'sixgr:truth:PUSCHCSIReceiveContextMismatch','Retain this context and its actual presence/length decisions.');
counts=[e.ResolvedCSI1BitCount e.ResolvedCSI2BitCount];
validateattributes(counts,{'numeric'},{'real','size',[1 2]});
assert(all(isnan(counts) | (isfinite(counts) & counts>=0 & counts==fix(counts))), ...
    'sixgr:truth:InvalidReceivedCSILength','Unknown lengths stay NaN; resolved lengths are nonnegative integers.');
[usable,crc]=sixgr.truth.puschCSIReceiverUsable(rx,parts{1},parts{2},counts);
observed.CRCPass=crc;
if ~usable, return; end
validateattributes(counts,{'numeric'},{'finite','integer','nonnegative'});
assert(isequal(e.CSIPart1DecodedBeforePart2,true) && ...
    isequal(string(e.CSI2LengthAuthority),"received_csi_part1_and_active_report_configuration") && ...
    counts(1)==report.part1BitCount(), ...
    'sixgr:truth:MissingReceivedCSILengthAuthority', ...
    'Received Part 1 and the installed report, never TX counts, must resolve CSI length.');
observed.Fields=report.decode(parts{1},parts{2});
observed.DecodeOk=true;
end
