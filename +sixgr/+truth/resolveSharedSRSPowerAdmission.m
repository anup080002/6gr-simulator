function [admitted, decision] = resolveSharedSRSPowerAdmission(state,cfg,ue,resourceSlot)
% Admission only: unavailable received power references do not create SRS IQ.
% The existing SRS transmitter still owns strict power/context validation.
% This implementation policy neither changes reference age nor substitutes
% geometry, another beam, configured SNR, or future receiver knowledge.
arguments
    state (1,1) struct
    cfg (1,1) struct
    ue (1,1) double {mustBeInteger,mustBePositive}
    resourceSlot (1,1) double {mustBeInteger,mustBePositive}
end
meta=sixgr.util.structGet(cfg,'lls6g.userContext',struct());
assert(ue<=state.NumUsers && resourceSlot==state.CurrentSlot && ...
    sixgr.util.structGet(meta,'UEIndex',NaN)==ue && ...
    sixgr.util.structGet(meta,'RuntimeCurrentSlot',NaN)==resourceSlot && ...
    string(sixgr.util.structGet(meta,'RuntimeCurrentDirection',""))=="UL", ...
    'sixgr:srs:PreparationAdmissionIdentity', ...
    'SRS admission requires the original UE-bound UL resource planning context.');
knowledgeSlot=resourceSlot;
if string(sixgr.util.structGet(state,'RuntimeViewMode',"execution"))=="future_ul_grant_planning"
    knowledgeSlot=state.PlanningDecisionSlot;
end
validateattributes(knowledgeSlot,{'numeric'}, ...
    {'real','scalar','finite','integer','positive','<=',resourceSlot});
required=sixgr.util.structGet(cfg,'rf.frontend.ul_power_control.require_measured_reference_rs',false);
assert((islogical(required)||isnumeric(required)) && isscalar(required) && ...
    isreal(required) && isfinite(double(required)) && any(required==[0 1]), ...
    'sixgr:srs:PreparationAdmissionPolicy','Measured-reference policy must be explicitly binary.');
referenceOnly=lower(strtrim(string(sixgr.util.structGet(cfg,'run.noiseOperatingMode',""))))== ...
    "standalone_awgn_snr_argument" || sixgr.rf.isNormalizedFixedSNRPowerReference(cfg);
required=logical(required) && ~referenceOnly;
admitted=true;
status="not_required_by_applied_power_mode";
reference=struct('ReferenceRS',"",'ReferenceSignalId',NaN, ...
    'MeasurementId',"",'ProducerSlot',NaN,'AvailableSlot',NaN);
maxAge=NaN;
if required
    configured=sixgr.phy.refsig.resolveConfiguredPathlossReference(cfg,'SRS');
    assert(configured.Available && configured.SignalType=="SSB", ...
        'sixgr:srs:PreparationAdmissionConfiguration', ...
        'Missing or unsupported SRS reference configuration is not an operational deferral.');
    % Recheck against the same original state and knowledge clock. A copied
    % or malformed bound capsule must not turn an integrity error into defer.
    reference=sixgr.truth.resolveSRSPowerReference(state,cfg,ue,resourceSlot);
    bound=sixgr.util.structGet(meta,'RuntimeSRSPowerReference',struct());
    assert(isstruct(bound) && isscalar(bound) && isfield(bound,'Usable') && ...
        islogical(bound.Usable) && isscalar(bound.Usable) && ...
        isequaln(bound,reference), ...
        'sixgr:srs:PreparationAdmissionContext', ...
        'Retain the exact original direction-specific SRS power-reference result.');
    admitted=reference.Usable;
    status=reference.Status;
    maxAge=reference.MaximumAgeSlots;
    if ~admitted
        operational=["no_measurements","no_matching_measurement", ...
            "future_measurement_not_available","stale", ...
            "no_available_decoded_sib1_power","reference_lifecycle_unavailable"];
        assert(any(status==operational), ...
            'sixgr:srs:PreparationAdmissionUnavailableReason', ...
            'Unsupported SRS reference status must fail, not defer: %s.',status);
    end
end
action="admit_SRS_power_reference";
if ~admitted, action="defer_SRS_unavailable_measured_power_reference"; end
decision=table(ue,"UL",double(knowledgeSlot),resourceSlot,required,logical(admitted), ...
    string(status),action,string(reference.ReferenceRS),double(reference.ReferenceSignalId), ...
    double(maxAge),string(reference.MeasurementId),double(reference.ProducerSlot), ...
    double(reference.AvailableSlot),false,false, ...
    "original_SRS_reference_preparation_admission", ...
    "preparation_admission_not_PHY_execution", ...
    'VariableNames',{'UEIndex','Direction','DecisionSlot','SRSResourceSlot', ...
    'MeasuredPowerReferenceRequired','PreparationAdmitted','PowerReferenceStatus','Action', ...
    'PowerReferenceRS','PowerReferenceSignalID','MaximumPowerReferenceAgeSlots', ...
    'PowerReferenceMeasurementID','PowerReferenceProducerSlot','PowerReferenceAvailableSlot', ...
    'SRSTransmissionPrepared','SRSReceiverExecuted','Source','EvidenceClass'});
decision.PathlossReferenceLifetime=string(sixgr.util.structGet(reference, ...
    'PathlossReferenceLifetime',"not_required_by_applied_power_mode"));
decision.ReferenceLifecycleStatus=string(sixgr.util.structGet(reference, ...
    'ReferenceLifecycleStatus',"not_required_by_applied_power_mode"));
end
