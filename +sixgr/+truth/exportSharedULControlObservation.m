function exportSharedULControlObservation(runFolder,cfg,prepared,planes,received)
% Actual full TX and received UL samples, not a continuous VSG playback claim.
if ~sixgr.util.persistenceEnabled() || ...
        ~logical(sixgr.util.structGet(cfg,'outputs.rawIQCaptureEnabled',false)) || ...
        ~logical(sixgr.util.structGet(cfg,'outputs.saveRawWaveforms',false)), return; end
[post,pre,tx,replay,receiver]=sixgr.truth.sharedObservationEvidence(planes,prepared);
layout=sixgr.report.resultLayout(runFolder);
folder=fullfile(layout.AirInterfaceMATDir,'ul_control_received_observations');
sixgr.util.ensureFolder(folder);
ids=string({planes.ReceiverID}); txID=extractBefore(ids(endsWith(ids,':tx')),':tx');
target=fullfile(folder,lower(prepared.Channel)+"_"+txID+"_tx_"+tx.StartSample+".mat");
assert(~isfile(target),'sixgr:truth:DuplicateULControlCapture','Do not overwrite a prior physical observation.');
capture=struct('Source',"actual_shared_physical_UL_control_observation", ...
    'Scope',"received_control_not_continuous_instrument_playback", ...
    'SampleRateHz',post.SampleRateHz,'TXStartSample',tx.StartSample, ...
    'TXEndSampleExclusive',tx.EndSampleExclusive,'RXStartSample',post.StartSample, ...
    'RXEndSampleExclusive',post.EndSampleExclusive,'Prepared',prepared, ...
    'TXAfterRF',tx.readComplete(),'RXBeforeRF',pre.readComplete(), ...
    'RXAfterRF',post.readComplete(),'RXAfterDigitalGainCompensation',receiver.readComplete(), ...
    'ExecutionReplay',replay,'ReceivedResult',received,'WaveformAmplitudeUnit',"sqrt_mW");
if prepared.Channel=="SRS"
    planeIDs=string({planes.ReceiverID});
    scoringID=planeIDs(endsWith(planeIDs,':desired_pre_noise'));
    [reference,evidence,channelReferences]=sixgr.truth.sharedLinkScoringObservation(planes,prepared,scoringID);
    capture.DesiredLinkScoringSamples=reference.readComplete();
    capture.DesiredLinkScoringEvidence=evidence;
    capture.AppliedChannelReferenceSegments=channelReferences;
end
% PUCCH/SRS captures need the same long-path-safe, byte-verified publication
% as data captures, without dropping IQ or changing the v7.3 payload format.
sixgr.util.matSave(target,struct('capture',capture), ...
    'UseArtifactStore',false,'ForceV73',true);
end
