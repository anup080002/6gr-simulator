function out=scoreSharedSSBPower(reception,desired,source,pre,replay,elementBinding,powerContext,original)
%SCORESHAREDSSBPOWER Optional original-link SSS-RE power comparison.
% Actual pre-RF receiver decisions and original element order are reused.
% The reference includes the ORIGINAL serving TX's RF distortion and any
% same-transmitter leakage on the SSS REs. It is NOT an isolated ideal SSS,
% pure-channel gain, standardized receiver-accuracy or hardware qualification.
% No result here is supplied to acquisition, reporting selection or scheduling.
out=defaults();
if nargin==0, return; end
e=struct('ContractVersion',"sixgr.ssb.original_link_power_comparison/v1", ...
    'Stage',"not_attempted",'ReferenceUsedByReceiver',false, ...
    'AdditionalRFExecutions',0,'AdditionalChannelExecutions',0, ...
    'AdditionalTimingAcquisitions',0,'AdditionalFrequencyEstimations',0, ...
    'AdditionalChannelEstimations',0,'AdditionalOFDMDemodulations',0, ...
    'AdditionalOFDMDemodulationAttempts',0, ...
    'IncludesOriginalTXRFNonlinearity',true,'IncludesReceiverRF',false, ...
    'IsolatedIdealSSSReference',false,'SameTransmitterLeakageExcluded',false, ...
    'StandardizedReferencePlaneQualified',false,'StandardizedAccuracyQualified',false, ...
    'StatisticallyQualified',false,'HardwareQualified',false);
try
    id='sixgr:truth:SSBPowerReference';
    assert(nargin==8,id,'Supply original received result, planes, execution, element binding and power context.');
    if ~logical(sixgr.util.structGet(reception,'SSBPowerMeasurementReceiptAvailable',false))
        out.SSBEmittedPowerComparisonStatus="unavailable_original_preRF_measurement_receipt";
        out=finish(out,e); return;
    end
    e.Stage="original_measurement_receipt";
    token=string(reception.SSBPowerMeasurementReceiptJSON);
    assert(isscalar(token)&&sha(token)==string(reception.SSBPowerMeasurementReceiptSHA256),id, ...
        'Original receiver receipt hash mismatch.');
    r=jsondecode(token);
    assert(r.Available&&~r.ReferenceUsedByReceiver&& ...
        r.NCellID==reception.NCellID&&r.ObservedSSBOccasionIndex==reception.ObservedSSBOccasionIndex,id, ...
        'Do not transplant another cell or SSB beam observation.');
    if ~r.FFTSupportAvailable
        out.SSBEmittedPowerComparisonStatus="unavailable_original_native_FFT_sample_support";
        out=finish(out,e); return;
    end
    e.Stage="original_sample_and_execution_identity";
    assert(isstruct(original)&&isscalar(original)&& ...
        all(isfield(original,{'Planes','DesiredReferencePlaneID'})),id, ...
        'Retain the original completed item plane binding, not a same-sized reference replacement.');
    planes=original.Planes; ids=string({planes.ReceiverID});
    iq=find(ids==string(original.DesiredReferencePlaneID));
    ip=find(ids==string(source.ReceiverID)+":pre_rf");
    it=find(ids==string(source.TransmitterID)+":tx");
    assert(isscalar(iq)&&isscalar(ip)&&isscalar(it)&& ...
        planes(iq).Observation==desired&&planes(ip).Observation==pre,id, ...
        'Reference and measurement must be the original completed observation instances.');
    assert(isa(pre,'sixgr.phy.waveform.WaveformObservationBuffer')&&isscalar(pre)&&pre.isComplete()&& ...
        isa(desired,'sixgr.phy.waveform.WaveformObservationBuffer')&&isscalar(desired)&&desired.isComplete()&& ...
        pre.StartSample==r.ObservationStartSample&&pre.EndSampleExclusive==r.ObservationEndSampleExclusive&& ...
        pre.SampleRateHz==r.ReceiverOperator.SampleRate_Hz&&pre.NumReceiveAntennas==r.NumReceiveColumns&& ...
        pre.sampleHash()==string(r.InputSHA256)&& ...
        desired.StartSample==pre.StartSample&&desired.EndSampleExclusive==pre.EndSampleExclusive&& ...
        desired.SampleRateHz==pre.SampleRateHz&&desired.NumReceiveAntennas==pre.NumReceiveAntennas,id, ...
        'Require exact original measured and desired-link capture bounds, hash and columns.');
    assert(string(source.Source)=="actual_executed_link_contribution"&& ...
        string(source.Scope)=="effective_pilot_response_includes_actual_tx_rf_not_isolated_pure_channel_matrix"&& ...
        source.StartSample==pre.StartSample&&source.EndSampleExclusive==pre.EndSampleExclusive&& ...
        ~source.ReceiverEstimatorInput&&~source.ReferenceGainFitted&& ...
        source.AdditionalChannelExecutions==0&&source.AdditionalRFExecutions==0&& ...
        string(source.ReceiverID)==string(replay.ReceiverID)&&strlength(string(source.LinkID))>0&& ...
        strlength(string(source.TransmitterID))>0,id,'Use original serving-link contribution without RF replay or fitting.');
    assert(string(r.WaveformAmplitudeUnit)==string(replay.WaveformAmplitudeUnit)&& ...
        string(r.WaveformAmplitudeUnit)==string(powerContext.WaveformAmplitudeUnit),id, ...
        'Original measured, executed and configured waveform units must agree.');
    element=sixgr.rf.validateReceiveElementObservation(pre,replay,elementBinding);
    if ~element.Available
        out.SSBEmittedPowerComparisonStatus="unavailable_original_receive_element_execution_binding";
        out=finish(out,e); return;
    end
    branch=sixgr.rf.validateReceiveBranchObservation(pre,replay, ...
        sixgr.util.structGet(original,'ReceiveBranchBinding',struct()));
    e.ReceiveElementBinding=element;
    e.ReceiveBranchBinding=branch;
    out.SSBReceiveElementBindingAvailable=element.Available;
    out.SSBReceiveElementReferencePlane=string(element.ReferencePlane);
    out.SSBReceiveElementBindingEvidenceJSON=string(jsonencode(element));
    out.SSBReceiveBranchBindingAvailable=branch.Available;
    out.SSBReceiveBranchReferencePlane=string(branch.ReferencePlane);
    out.SSBReceiveBranchBindingEvidenceJSON=string(jsonencode(branch));
    intervals=double(source.Intervals); active=logical(source.LinkActive(:));
    assert(size(intervals,2)==2&&size(intervals,1)==numel(active)&& ...
        all(intervals(:,2)>intervals(:,1))&&all(intervals(2:end,1)==intervals(1:end-1,2)),id, ...
        'Original desired-link interval coverage must be contiguous.');
    segments=planes(iq).Segments;
    assert(iscell(segments)&&numel(segments)==size(intervals,1),id, ...
        'Source metadata must describe the original desired-plane execution intervals.');
    for k=1:numel(segments)
        segment=segments{k}; entries=segment.Execution.ScoringPlanes;
        entry=entries(string({entries.ID})==string(original.DesiredReferencePlaneID));
        assert(isscalar(entry)&&string(entry.RX)==string(source.ReceiverID)&& ...
            string(entry.LinkID)==string(source.LinkID)&& ...
            string(entry.Source)=="actual_link_contribution_after_tx_rf_channel_loss_before_sum_noise_rx_rf"&& ...
            (~entry.Active||string(entry.TX)==string(source.TransmitterID))&& ...
            entry.Active==active(k)&&isequal(intervals(k,:),[segment.StartSample segment.EndSampleExclusive]),id, ...
            'Do not transplant another serving link, active interval or source identity.');
    end
    support=double(r.SSSFFTIntervalCaptureLocal0(:).')+pre.StartSample;
    hits=intervals(:,1)<support(2)&intervals(:,2)>support(1);
    assert(any(hits)&&all(active(hits))&&intervals(find(hits,1),1)<=support(1)&& ...
        intervals(find(hits,1,'last'),2)>=support(2),id, ...
        'The desired direction must be physically active over every original SSS FFT sample.');
    e.Stage="original_measured_value_binding";
    measured=double(r.OriginalMeasuredPowerPerReceiveColumn(:).');
    normalized=string(r.WaveformAmplitudeUnit)=="normalized_complex_baseband";
    suffix="_dBm"; offset=30;
    if normalized, suffix="_dB_re_UnitOccupiedRE_Es"; offset=0; end
    measuredLogValues=str2double(split(string(reception.("SS_RSRPPerReceiveAntenna"+suffix)),"|"));
    expected=nan(size(measured)); positive=measured>0;
    expected(positive)=10*log10(measured(positive))+offset;
    assert(numel(measuredLogValues)==numel(expected)&&isequal(isnan(measuredLogValues(:)),isnan(expected(:))),id, ...
        'Preserve logarithmically unavailable original nonpositive measurements.');
    assert(all(abs(measuredLogValues(positive)-expected(positive).')<1e-10),id, ...
        'Original serialized per-column power must derive from the unchanged original linear operands.');
    scalar=double(reception.("SS_RSRP"+suffix));
    if any(positive)
        assert(isfinite(scalar)&&abs(scalar-max(expected,[],'omitnan'))<1e-10,id, ...
            'Keep original selected measurement, never replace it by the reference maximum.');
    else
        assert(isnan(scalar),id,'No positive original received power exists.');
    end
    e.ObservationStartSample=pre.StartSample; e.ObservationEndSampleExclusive=pre.EndSampleExclusive;
    e.NCellID=r.NCellID; e.ObservedSSBOccasionIndex=r.ObservedSSBOccasionIndex;
    e.LinkID=string(source.LinkID); e.TransmitterID=string(source.TransmitterID); e.ReceiverID=string(source.ReceiverID);
    e.OriginalDesiredReferencePlaneID=string(original.DesiredReferencePlaneID);
    e.OriginalMeasurementReceiptSHA256=sha(token); e.OriginalInputSHA256=string(r.InputSHA256);
    e.OriginalReceiveElementLayoutSHA256=string(element.Layout.LayoutSHA256);
    e.OriginalReceiveElementExecutionSHA256=string({element.IntervalReceipts.ReceiptSHA256});
    e.OriginalPreRFOperator=r.ReceiverOperator;
    e.Stage="replay_original_operator_for_scoring_only";
    e.AdditionalOFDMDemodulationAttempts=1;
    comparison=sixgr.phy.refsig.replaySSBPowerMeasurementOperator(desired.readComplete(),r);
    e.AdditionalOFDMDemodulations=comparison.AdditionalOFDMDemodulations;
    e.Comparison=comparison;
    out.SSBEmittedPowerComparisonAvailable=comparison.ReferenceMaximumPower>0;
    out.SSBEmittedPowerComparisonStatus="available_original_link_SSS_RE_power_model_comparison";
    if ~out.SSBEmittedPowerComparisonAvailable
        out.SSBEmittedPowerComparisonStatus="unavailable_nonpositive_original_reference_power";
    end
    out.SSBEmittedPowerComparisonUnit=comparison.LinearPowerUnit;
    out.SSBEmittedPowerComparisonReportedError_dB=comparison.ReportedError_dB;
    out.SSBEmittedPowerComparisonSelectedColumnError_dB=comparison.MeasuredSelectedColumnError_dB;
    e.Stage="completed_optional_power_comparison";
catch failure
    bindingFields=out;
    out=defaults();
    for name=["SSBReceiveElementBindingAvailable","SSBReceiveElementReferencePlane", ...
            "SSBReceiveElementBindingEvidenceJSON","SSBReceiveBranchBindingAvailable", ...
            "SSBReceiveBranchReferencePlane","SSBReceiveBranchBindingEvidenceJSON"]
        out.(name)=bindingFields.(name);
    end
    out.SSBEmittedPowerComparisonStatus="unavailable_original_reference_comparison_failed";
    out.SSBEmittedPowerComparisonErrorIdentifier=string(failure.identifier);
    e.ErrorIdentifier=string(failure.identifier); e.ErrorMessage=string(failure.message);
end
out=finish(out,e);
end

function out=defaults()
out=struct('SSBEmittedPowerComparisonAvailable',false, ...
    'SSBEmittedPowerComparisonStatus',"unavailable_original_desired_link_reference", ...
    'SSBEmittedPowerComparisonEvidenceJSON',"",'SSBEmittedPowerComparisonEvidenceSHA256',"", ...
    'SSBEmittedPowerComparisonErrorIdentifier',"",'SSBEmittedPowerComparisonUnit',"", ...
    'SSBEmittedPowerComparisonReferencePlane',"internal_physical_receive_element_before_RX_front_end", ...
    'SSBEmittedPowerComparisonScope',"desired_link_SSS_RE_power_including_original_TX_RF_and_same_TX_leakage", ...
    'SSBEmittedPowerComparisonReportedError_dB',NaN,'SSBEmittedPowerComparisonSelectedColumnError_dB',NaN, ...
    'SSBEmittedPowerComparisonStandardizedAccuracyQualified',false, ...
    'SSBReceiveElementBindingAvailable',false,'SSBReceiveElementReferencePlane',"unavailable_original_element_binding", ...
    'SSBReceiveElementBindingEvidenceJSON',"",'SSBReceiveBranchBindingAvailable',false, ...
    'SSBReceiveBranchReferencePlane',"unavailable_original_branch_binding",'SSBReceiveBranchBindingEvidenceJSON',"", ...
    'SSBMeasurementStandardizedReferencePointQualified',false,'SSBMeasurementHardwareQualified',false);
end
function out=finish(out,e)
e.Available=out.SSBEmittedPowerComparisonAvailable; e.Status=out.SSBEmittedPowerComparisonStatus;
out.SSBEmittedPowerComparisonEvidenceJSON=string(jsonencode(e));
out.SSBEmittedPowerComparisonEvidenceSHA256=sha(out.SSBEmittedPowerComparisonEvidenceJSON);
end
function value=sha(token)
value=string(sixgr.util.sha256Hex(char(token)));
end
