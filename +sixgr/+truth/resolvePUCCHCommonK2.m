function [slots,evidence]=resolvePUCCHCommonK2(state,cfg,ue,policy,context)
% Resolve actual received common IE or an explicitly configured RRC boundary.
% Connected dedicated UL TDRA is deliberately not a source of common K2.
kind=string(policy.received_dci_autonomous_policy);
slots=zeros(1,0); evidence=struct('Source',"unsupported_autonomous_response_only");
if kind=="response_only", return; end
id='sixgr:truth:PUCCHCommonK2Binding';
received=struct();
items=sixgr.util.structGet(state,'UECommonCellConfigurationByUE',{});
if numel(items)>=ue && isstruct(items{ue}) && ...
        isfield(items{ue},'PUSCHCommonTiming') && items{ue}.PUSCHCommonTiming.Available
    common=items{ue}; timing=common.PUSCHCommonTiming;
    recoveries=sixgr.util.structGet(state,'DecodedSIB1RecoveryByUE',{});
    assert(numel(recoveries)>=ue,id,'Retain the original received-common delivery owner.');
    rx=recoveries{ue};
    assert(isstruct(rx) && isscalar(rx) && ...
        all(isfield(rx,{'SIB1RxTreeHash','ReceivedSIB1AvailableAtSample'})),id, ...
        'Retain the original decoded SIB1 tree identity and its delivery sample.');
    assert((ischar(rx.SIB1RxTreeHash) && isrow(rx.SIB1RxTreeHash) || ...
        isstring(rx.SIB1RxTreeHash) && isscalar(rx.SIB1RxTreeHash)) && ...
        isnumeric(rx.ReceivedSIB1AvailableAtSample) && isscalar(rx.ReceivedSIB1AvailableAtSample) && ...
        isfinite(rx.ReceivedSIB1AvailableAtSample) && rx.ReceivedSIB1AvailableAtSample>=0 && ...
        rx.ReceivedSIB1AvailableAtSample==fix(rx.ReceivedSIB1AvailableAtSample),id, ...
        'Received-common identity and delivery sample must retain their original scalar types.');
    now=state.SharedWaveformStream.Events.NextSampleIndex;
    assert(islogical(common.PUSCHConfigCommonPresent)&&common.PUSCHConfigCommonPresent && ...
        common.Source=="decoded_sib1" && common.ServingCell==cfg.lls6g.userContext.RuntimeServingCell && ...
        timing.PayloadHash==common.PayloadHash && timing.TreeHash==common.TreeHash && ...
        string(rx.SIB1RxTreeHash)==common.TreeHash && ...
        rx.ReceivedSIB1AvailableAtSample<=now && ...
        timing.ConfigurationSource=="decoded_sib1" && ...
        cfg.phy.frame.DefaultIdentity.ULBWPID==0 && ...
        common.InitialULBWP.StartRB==context.Data.ActiveULBWPStart && ...
        common.InitialULBWP.SizeRB==context.Data.ActiveULBWPSize && ...
        common.InitialULBWP.SubcarrierSpacing_kHz==cfg.phy.carrier.SubcarrierSpacing, ...
        id,'Common K2 must belong to this delivered initial/active UL BWP, cell and numerology.');
    assert(~isempty(regexp(char(common.PayloadHash),'^[0-9a-fA-F]{64}$','once')) && ...
        ~isempty(regexp(char(common.TreeHash),'^[0-9a-fA-F]{64}$','once')),id, ...
        'Retain original received SIB1 payload/tree hashes.');
    % Revalidate the original received operands, including the standard
    % absent-k2-field rule; absent whole lists do not manufacture rows.
    original=sixgr.rrc.asn1.resolvePUSCHConfigCommon(common.PUSCHConfigCommon, ...
        common.InitialULBWP.SubcarrierSpacing_kHz);
    assert(isequal(double(original.K2Slots),double(timing.K2Slots)) && ...
        isequal(original.K2Present,timing.K2Present),id,'Installed common timing operands changed.');
    received=struct('Source',"original_received_PUSCH_ConfigCommon",'Timing',timing, ...
        'PayloadHash',common.PayloadHash,'TreeHash',common.TreeHash, ...
        'AvailableAtSample',rx.ReceivedSIB1AvailableAtSample,'ServingCell',common.ServingCell, ...
        'ConfigurationEpoch',common.ConfigurationEpoch,'ActiveULBWP',0);
end
if kind=="received_common_k2"
    assert(~isempty(fieldnames(received)),id,'Autonomous CSI/SR requires the original delivered common K2 list.');
    slots=reshape(double(received.Timing.K2Slots),1,[]); evidence=received;
elseif kind=="configured_common_k2"
    slots=reshape(double(policy.received_dci_common_k2_slots),1,[]);
    if ~isempty(fieldnames(received))
        assert(isequal(slots,reshape(double(received.Timing.K2Slots),1,[])),id, ...
            'Configured common timing cannot contradict original received common operands.');
    end
    evidence=struct('Source',"explicit_configured_PUSCH_ConfigCommon_not_decoded_RRC", ...
        'K2Slots',slots,'ServingCell',cfg.lls6g.userContext.RuntimeServingCell, ...
        'ActiveULBWP',cfg.phy.frame.DefaultIdentity.ULBWPID,'ReceivedComparison',received);
else
    error(id,'Unknown autonomous common timing policy.');
end
assert(~isempty(slots)&&all(isfinite(slots)&slots>=0&slots==fix(slots)),id,'No invented minimum for an absent list.');
end
