function [state,next,cp]=prepareCellContentionResponse(state,cfg,cp)
% Cell-owned common-control admission after actual Msg3 decoding.
% A common Msg4 CORESET cannot carry two overlapping independently encoded
% DCIs. Serialize those occasions, and their configured SRB1 allocations,
% within the real UE contention window. UE monitoring remains independent.
assert(cp.NextStage==4 && cp.ResumePhase=="decoded", ...
    'sixgr:truth:ContentionResponseBoundary','Plan contention response after completed Msg3 only.');
if ~logical(sixgr.util.structGet(cp.Msg3Rx,'Ok',false))
    [next,cp]=sixgr.phy.ra.runFourStepRA(cfg,'Continuation',cp,'StageAction','prepare_next_stage');
    return;
end
ra=cp.RAConfig; timing=ra.TimingSchedule;
reservations=sixgr.util.structGet(state,'GNBContentionReservations',struct([]));
frame=sixgr.phy.FrameStructureEngine(cp.Config,'FrameCoreOnly',true);
common=sixgr.phy.frame.CommonDLResourcePlan(cp.Config); common.validateSIB1References();
window=ra.RARMonitoringWindow;
hit=window.MonitoringSlots==ra.Msg2Slot;
window.MonitoringSlots=window.MonitoringSlots(hit);
window.MonitoringStartTicks=window.MonitoringStartTicks(hit);
plan=sixgr.phy.ia.RAEventScheduler.resolve( ...
    'PDSCHResourceAvailability',@available, ...
    'RARMonitoringWindow',window,'PRACHOccasionEndSlot',ra.PRACHOccasionEndSlot, ...
    'RAResponseWindowSlots',ra.RAResponseWindowSlots, ...
    'RARProcessingDelaySlots',max(1,ra.Msg2Slot-ra.PRACHOccasionEndSlot), ...
    'Msg3K2Slots',cp.GrantRx.K2,'Msg3TimeDomainAllocation',cp.GrantRx.TimeDomainAllocation, ...
    'Msg4ProcessingDelaySlots',timing.Msg4ProcessingDelaySlots, ...
    'ContentionResolutionTimerSlots',ra.RAContentionResolutionTimerSlots, ...
    'SetupCompleteK2Slots',timing.SetupCompleteK2Slots, ...
    'RequireSetupComplete',ra.RequireRRCSetupComplete,'FrameEngine',frame, ...
    'Msg2SymbolAllocation',[ra.Msg2PDSCH.SymbolStart ra.Msg2PDSCH.NumSymbols], ...
    'Msg4SymbolAllocation',[ra.Msg4PDSCH.SymbolStart ra.Msg4PDSCH.NumSymbols], ...
    'SetupCompleteSymbolAllocation',[ra.SetupCompletePUSCH.SymbolStart ra.SetupCompletePUSCH.NumSymbols]);
assert(plan.Msg2Slot==ra.Msg2Slot && plan.Msg3Slot==ra.Msg3Slot, ...
    'sixgr:truth:FrozenRAHistoryChanged','Contention scheduling cannot move executed Msg2/Msg3.');
ra.TimingSchedule=plan; ra.Msg4Slot=plan.Msg4Slot; ra.SetupCompleteSlot=plan.SetupCompleteSlot;
cp.RAConfig=ra; cp.Timing=sixgr.phy.ia.RATimingService.fromRAPlan(ra);
cp.Result.Msg4ScheduledSlot=ra.Msg4Slot; cp.Result.SetupCompleteScheduledSlot=ra.SetupCompleteSlot;
[next,cp]=sixgr.phy.ra.runFourStepRA(cfg,'Continuation',cp,'StageAction','prepare_next_stage');
assert(~isempty(fieldnames(next.PreparedTransmission)) && next.PreparedTransmission.StageName=="Msg4", ...
    'sixgr:truth:ContentionReservationWithoutTransmission','Reserve only an actual prepared Msg4.');
entry=struct('ServingCell',ra.ServingCell,'TemporaryCRNTI',ra.TempCRNTI, ...
    'Msg4Slot',ra.Msg4Slot,'SetupCompleteSlot',ra.SetupCompleteSlot, ...
    'RequireSetupComplete',ra.RequireRRCSetupComplete);
if isempty(reservations), reservations=entry; else, reservations(end+1)=entry; end
state.GNBContentionReservations=reservations;

    function [ok,evidence]=available(stage,slot)
        allocation=ra.Msg2PDSCH;
        if stage=="Msg4", allocation=ra.Msg4PDSCH; end
        [ok,evidence]=common.checkPDSCH(allocation,slot);
        if ~ok || stage~="Msg4" || isempty(reservations), return; end
        same=[reservations.ServingCell]==ra.ServingCell;
        collision=same & ([reservations.Msg4Slot]==slot | ...
            (ra.RequireRRCSetupComplete & [reservations.RequireSetupComplete] & ...
            [reservations.SetupCompleteSlot]==slot+timing.SetupCompleteK2Slots));
        if any(collision)
            ok=false; evidence=struct('Reason',"cell_common_control_or_srb1_already_reserved", ...
                'AbsoluteSlot0',slot);
        end
    end
end
