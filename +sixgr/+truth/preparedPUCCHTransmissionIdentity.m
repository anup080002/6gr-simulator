function identity=preparedPUCCHTransmissionIdentity(prepared,ue,observationID)
% UE-owned preparation identity, not gNB knowledge or execution evidence.
assert(isa(prepared,'sixgr.link.PreparedUplinkControlTransmission') && ...
    isscalar(prepared) && prepared.Channel=="PUCCH", ...
    'sixgr:truth:PreparedPUCCHIdentityRequired','Retain the typed PUCCH preparation.');
validateattributes(ue,{'numeric'},{'scalar','real','finite','integer','positive'});
observationID=string(observationID);
assert(isscalar(observationID) && strlength(strtrim(observationID))>0, ...
    'sixgr:truth:PreparedPUCCHObservationRequired','Bind the registered physical observation.');
assignment=prepared.RequestBinding.Assignment;
report=prepared.RequestBinding.Report;
assert(isa(assignment,'sixgr.phy.pucch.PUCCHTransmissionAssignment') && isscalar(assignment) && ...
    isa(report,'sixgr.phy.pucch.UCIReport') && isscalar(report) && ...
    assignment.Data.UEID==ue && assignment.ReportID==report.ReportID && ...
    assignment.Data.RNTI==report.Data.RNTI && ...
    assignment.ConfigurationEpoch==report.ConfigurationEpoch && ...
    assignment.DueSlot==report.Data.TargetSlot, ...
    'sixgr:truth:PreparedPUCCHUEIdentityMismatch','PUCCH assignment, report and UE ownership must agree.');
epoch=prepared.ReceiverConfig.rf.configurationEpoch;
validateattributes(epoch,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
identity=struct('ObservationID',observationID,'UEIndex',double(ue), ...
    'RNTI',double(assignment.Data.RNTI),'RFConfigurationEpoch',double(epoch), ...
    'UCIConfigurationEpoch',assignment.ConfigurationEpoch, ...
    'AssignmentDigest',assignment.Digest,'ReportDigest',report.Digest, ...
    'StartSample',prepared.StartSample,'EndSampleExclusive',prepared.EndSampleExclusive, ...
    'SampleRateHz',prepared.SampleRateHz);
identity.TransmissionID=sixgr.l2.mac.MACHash.of(orderfields(identity));
end
