function state=recordMACControlTransport(state,binding,identity,stage,sample,crc,status)
% Only actual physical-owner TX/RX callbacks; zero application credit.
assert(binding.ControlOnly&&binding.ApplicationPayloadBytes==0&&binding.Direction==identity.Direction&& ...
    any(binding.TransportKind==["RLC_STATUS","MAC_CE_PADDING"]), ...
    'sixgr:protocol:MACControlOwner','Original typed control-only transport required.');
row=table(string(binding.TBID),string(identity.TransmissionID),double(identity.UEIndex), ...
    double(identity.RNTI),string(binding.BearerID),string(binding.Direction),string(binding.TransportKind), ...
    double(binding.ConfigurationEpoch),string(stage),double(sample),double(identity.SampleRateHz), ...
    double(crc),string(status),string(binding.MACSHA256),0, ...
    'VariableNames',{'TransportBlockID','TransmissionID','UEIndex','RNTI','BearerID','Direction', ...
    'TransportKind','ConfigurationEpoch','Stage','Sample','SampleRateHz','CRCPass', ...
    'Status','MACSHA256','ApplicationCreditedBits'});
state.MACControlTransportLedgerTable=[sixgr.util.structGet(state,'MACControlTransportLedgerTable',table());row];
if binding.TransportKind=="RLC_STATUS"
    state=sixgr.truth.recordRLCStatusTransport(state,binding,identity,stage,sample,crc,status);
end
end
