function fields=harqFeedbackReceiveTimingFields(harq,grant,required)
% Preserve receive-event lineage before HARQ mutation. Missing legacy input
% is explicitly unavailable, not inferred from a source slot or CPU timer.
fields=struct('DataTransmitSymbolStartSample',NaN,'DataTransmitSymbolEndSampleExclusive',NaN, ...
    'DataTransmitSampleRateHz',NaN,'DataTransmitTimingSource',"", ...
    'DataReceiveSymbolStartSample',NaN, ...
    'DataReceiveSymbolEndSampleExclusive',NaN,'DataDecodeAvailableAtSample',NaN, ...
    'DataReceiveSampleRateHz',NaN,'DataReceiveTimingSource',"", ...
    'DataReceiveTimingEvidenceJSON',"");
e=sixgr.util.structGet(harq,'ReceivedTimingEvidence',struct());
if isstruct(e) && isscalar(e) && isempty(fieldnames(e))
    assert(~required,'sixgr:truth:MissingSharedHARQReceiveTiming', ...
        'Shared HARQ processing requires the actual received allocation and result-availability clock.');
    return;
end
names={'ContractVersion','Direction','RNTI','GrantContextId','DataAbsoluteSlot', ...
    'SymbolAllocation','SampleRateHz','ObservationStartSample','ObservationEndSampleExclusive', ...
    'AppliedTimingCorrectionSamples','ReceivedSymbolStartSample','ReceivedSymbolEndSampleExclusive', ...
    'ResultAvailableAtSample','Source','ProcessingBudgetIncluded'};
assert(isstruct(e) && isscalar(e) && all(isfield(e,names)), ...
    'sixgr:truth:InvalidSharedHARQReceiveTiming','The receive timing contract is incomplete.');
for name=["ObservationStartSample","ObservationEndSampleExclusive", ...
        "AppliedTimingCorrectionSamples","ReceivedSymbolStartSample", ...
        "ReceivedSymbolEndSampleExclusive","ResultAvailableAtSample","DataAbsoluteSlot"]
    validateattributes(e.(name),{'numeric'},{'scalar','real','finite','integer','nonnegative'});
end
validateattributes(e.SampleRateHz,{'numeric'},{'scalar','real','finite','positive'});
assert(string(e.ContractVersion)=="received_data_symbol_timing/v1" && ...
    string(e.Source)=="actual_received_reference_alignment_and_executed_OFDM_symbol_lengths" && ...
    ~e.ProcessingBudgetIncluded && ...
    e.ReceivedSymbolStartSample>=e.ObservationStartSample+e.AppliedTimingCorrectionSamples && ...
    e.ReceivedSymbolEndSampleExclusive>e.ReceivedSymbolStartSample && ...
    e.ReceivedSymbolEndSampleExclusive<=e.ObservationEndSampleExclusive && ...
    e.ResultAvailableAtSample>=e.ObservationEndSampleExclusive && ...
    string(e.Direction)==upper(string(grant.Direction)) && e.RNTI==grant.RNTI && ...
    string(e.GrantContextId)==string(grant.PHYGrant.GrantContextId) && ...
    e.DataAbsoluteSlot==grant.ScheduledAbsoluteSlot && ...
    isequal(double(e.SymbolAllocation(:)),double(grant.SymbolAllocation(:))), ...
    'sixgr:truth:SharedHARQReceiveTimingMismatch', ...
    'The received event must belong to this executed allocation, RNTI and immutable grant.');
fields.DataReceiveSymbolStartSample=e.ReceivedSymbolStartSample;
fields.DataReceiveSymbolEndSampleExclusive=e.ReceivedSymbolEndSampleExclusive;
fields.DataDecodeAvailableAtSample=e.ResultAvailableAtSample;
fields.DataReceiveSampleRateHz=e.SampleRateHz;
fields.DataReceiveTimingSource=e.Source;
fields.DataReceiveTimingEvidenceJSON=string(jsonencode(e));
% Legacy received-only records remain unavailable for transmitted-to-feedback
% latency. Never substitute their receive origin or configured slot boundary.
txNames={'TransmitWaveformStartSample','TransmitWaveformEndSampleExclusive', ...
    'TransmittedSymbolStartSample','TransmittedSymbolEndSampleExclusive'};
if any(isfield(e,txNames))
    assert(all(isfield(e,txNames)),'sixgr:truth:IncompleteHARQTransmitClock', ...
        'Transmit latency requires the complete executed waveform/symbol interval.');
    for name=string(txNames)
        validateattributes(e.(name),{'numeric'},{'scalar','real','finite','integer','nonnegative'});
    end
    assert(e.TransmittedSymbolStartSample>=e.TransmitWaveformStartSample && ...
        e.TransmittedSymbolEndSampleExclusive>e.TransmittedSymbolStartSample && ...
        e.TransmittedSymbolEndSampleExclusive<=e.TransmitWaveformEndSampleExclusive, ...
        'sixgr:truth:InvalidHARQTransmitClock','Scored symbols must belong to the actually transmitted waveform.');
    fields.DataTransmitSymbolStartSample=e.TransmittedSymbolStartSample;
    fields.DataTransmitSymbolEndSampleExclusive=e.TransmittedSymbolEndSampleExclusive;
    fields.DataTransmitSampleRateHz=e.SampleRateHz;
    fields.DataTransmitTimingSource="executed_prepared_waveform_origin_and_OFDM_symbol_lengths";
end
end
