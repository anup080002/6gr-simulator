function policy=resolveServingSSBTrackingPolicy(cfg)
% Keep actual periodic SS/PBCH observations available to every power
% consumer. Initial acquisition success does not remove the PRACH retry
% requirement for decoded SIB1 power minus measured, fresh serving-SSB RSRP.
% This policy schedules observations; it does not manufacture measurements,
% extend their validity, select a beam, or change acquisition/access state.
paths=[ ...
    "phy.pusch.power_control.require_measured_reference_rs", ...
    "phy.pusch.powerControl.requireMeasuredReferenceRS", ...
    "lls6g.pucch_resources.power_control.require_measured_reference_rs", ...
    "lls6g.resolvedConfig.pucch_resources.power_control.require_measured_reference_rs", ...
    "validation.pucch_resources.power_control.require_measured_reference_rs", ...
    "pucch_resources.power_control.require_measured_reference_rs"];
connected=false;
for path=paths
    value=sixgr.util.structGet(cfg,path,[]);
    if ~isempty(value) && logical(value)
        connected=true;
        break;
    end
end
reference=sixgr.phy.refsig.resolveConfiguredPathlossReference(cfg);
connectedSSB=connected && logical(reference.Available) && ...
    upper(string(reference.SignalType))=="SSB";
% The actual waveform scheduler uses phy.prach.enable. PRACH's selected
% SSB is independent of a connected PUSCH/PUCCH CSI-RS spatial relation.
% Normalized fixed-Es/N0 still needs acquisition/SIB1, but its PRACH power
% deliberately does not consume an absolute pathloss measurement.
raSSB=logical(sixgr.util.structGet(cfg,'phy.prach.enable',false)) && ...
    ~sixgr.rf.isNormalizedFixedSNRPowerReference(cfg);
policy=struct('Required',logical(connectedSSB || raSSB), ...
    'ConnectedMeasuredPathlossReferenceRequired',connected, ...
    'ConnectedSSBPowerReferenceRequired',logical(connectedSSB), ...
    'RASSBPowerReferenceRequired',logical(raSSB), ...
    'Source',"configured_consumers_of_actual_serving_ssb_measurements");
end
