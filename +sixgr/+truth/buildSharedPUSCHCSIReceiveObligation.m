function [obligation,report,calendar]=buildSharedPUSCHCSIReceiveObligation(cfg,grant)
% Independent periodic CSI schema for an overlapping scheduled PUSCH.
% No pending report, UE measurement, transmitted payload or producer status
% participates. The coordinator must separately resolve physical ownership.
obligation=struct('ReportConfigID',"",'ConfigurationEpoch',NaN);
report=[]; calendar=table();
assert(isstruct(grant) && isscalar(grant) && isfield(grant,'TimingDecision') && ...
    isstruct(grant.TimingDecision) && isscalar(grant.TimingDecision) && ...
    isfield(grant.TimingDecision,'DataAbsoluteSlot'), ...
    'sixgr:truth:MissingScheduledPUSCHCSIGrant','Use the canonical scheduled UL grant.');
sixgr.phy.grant.assertGrantTimingIdentity(grant,'UL');
enabled=sixgr.util.structGet(cfg,'phy.csi.reportCSI',false);
assert((islogical(enabled)||isnumeric(enabled)) && isscalar(enabled) && ...
    isreal(enabled) && isfinite(enabled) && any(enabled==[0 1]), ...
    'sixgr:truth:InvalidScheduledPUSCHCSIConfiguration','CSI enablement must be a scalar binary flag.');
if ~enabled, return; end
assert(string(sixgr.util.structGet(cfg,'phy.csi.reportTrigger',""))=="periodic", ...
    'sixgr:truth:UnsupportedScheduledPUSCHCSITrigger', ...
    'Nonperiodic CSI needs its independent activation/request authority; do not infer it from a UE report.');
identity=cfg.phy.frame.DefaultIdentity;
t=grant.TimingDecision;
assert(string(t.ScheduledCCID)==string(identity.ScheduledCCID) && ...
    string(t.TargetBWPID)==string(identity.ULBWPID), ...
    'sixgr:truth:ScheduledPUSCHCSIBWPMismatch', ...
    'The CSI calendar and scheduled UL grant must use the same resolved carrier/BWP.');
ue=struct('UEID',grant.UEIndex,'RNTI',grant.RNTI, ...
    'ServingCell',grant.ServingCell,'PUCCHCell',grant.ServingCell, ...
    'ComponentCarrier',identity.ScheduledCCID,'ActiveULBWP',identity.ULBWPID);
slot=double(t.DataAbsoluteSlot)+1;
calendar=sixgr.truth.buildPeriodicCSIReportObligations(cfg,ue,slot,slot);
if isempty(calendar), return; end
assert(height(calendar)==1,'sixgr:truth:AmbiguousScheduledPUSCHCSI', ...
    'Resolve multiple configured CSI reports explicitly before receiving this PUSCH.');
symbols=grant.SymbolAllocation;
overlap=symbols(1)<calendar.StartSymbol+calendar.NumSymbols && ...
    calendar.StartSymbol<sum(symbols);
if ~calendar.ULResourceAvailable || ~overlap, return; end
installed=sixgr.phy.mimo.CSIReportConfiguration( ...
    cfg.phy.csi.reportConfiguration,cfg.phy.csi.reportConfigurationEpoch);
report=installed.forTransport('PUSCH');
report.assertQualifiedWireLayout();
assert(report.ReportConfigID==calendar.CSIReportConfigID && ...
    report.Epoch==calendar.CSIConfigurationEpoch, ...
    'sixgr:truth:ScheduledPUSCHCSIConfigurationMismatch', ...
    'Retain the installed report identity/epoch when selecting PUSCH wire layout.');
obligation=struct('ReportConfigID',report.ReportConfigID,'ConfigurationEpoch',report.Epoch);
end
