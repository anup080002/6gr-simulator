function measurement=measureWaveformGainEnergy(before,after,amplitudeUnit)
% Scoring-only sample energies at the two sides of an executed gain stage.
% No configured gain, reference waveform or receiver estimate is an input.
% A numeric array alone cannot establish absolute milliwatts.
if nargin<3, amplitudeUnit="input_amplitude"; end
amplitudeUnit=string(amplitudeUnit);
assert(isscalar(amplitudeUnit) && any(amplitudeUnit== ...
    ["input_amplitude","normalized_complex_baseband","sqrt_mW"]), ...
    'sixgr:truth:InvalidGainEnergyUnit','Retain the executed waveform amplitude unit.');
assert((isa(before,'double') || isa(before,'single')) && ...
    strcmp(class(before),class(after)) && ismatrix(before) && ...
    isequal(size(before),size(after)) && ~isempty(before) && ...
    all(isfinite(before(:))) && all(isfinite(after(:))), ...
    'sixgr:truth:InvalidGainEnergySamples', ...
    'Measure finite, same-sized actual input/output samples in one numeric domain.');
measurement=struct('InputEnergy',sum(abs(double(before(:))).^2), ...
    'OutputEnergy',sum(abs(double(after(:))).^2), ...
    'InputEnergy_mWsample',NaN,'OutputEnergy_mWsample',NaN, ...
    'AmplitudeUnit',amplitudeUnit,'EnergyUnit',"sum_squared_input_amplitude", ...
    'SampleElementCount',numel(before),'SampleCount',size(before,1), ...
    'BranchCount',size(before,2), ...
    'Source',"actual_samples_before_after_large_scale_gain", ...
    'ReceiverEstimatorInput',false);
if amplitudeUnit=="sqrt_mW"
    measurement.InputEnergy_mWsample=measurement.InputEnergy;
    measurement.OutputEnergy_mWsample=measurement.OutputEnergy;
    measurement.EnergyUnit="mW_sample_not_joules";
elseif amplitudeUnit=="normalized_complex_baseband"
    measurement.EnergyUnit="sum_squared_normalized_complex_amplitude_not_mW";
end
% Conservative floating-point allowance: sample multiplication/casting plus
% double-precision accumulation. This is not a propagation-model tolerance.
measurement.RelativeTolerance=64*double(eps(class(before)))+8*numel(before)*eps;
assert(isfinite(measurement.InputEnergy) && ...
    isfinite(measurement.OutputEnergy), ...
    'sixgr:truth:GainEnergyOverflow','Executed sample energy is not representable.');
end
