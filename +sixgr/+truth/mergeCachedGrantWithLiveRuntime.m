function grantOut = mergeCachedGrantWithLiveRuntime(grantCached, grantLive)
%MERGECACHEDGRANTWITHLIVERUNTIME Merge immutable cache with live occasion state.
%   The resolved-grant cache owns transport-block/coding fields that must
%   remain stable across HARQ retransmissions.  HARQ-ACK multiplexing is
%   different: it is created for one UL occasion and must always come from
%   the current runtime grant.  Replaying those fields from the original
%   transmission can consume an already-finalized PUCCH/HARQ row.

grantOut = grantCached;
if ~(isstruct(grantOut) && isscalar(grantOut) && ...
        ~isempty(fieldnames(grantOut)))
    grantOut = grantLive;
end
if ~(isstruct(grantLive) && isscalar(grantLive) && ...
        ~isempty(fieldnames(grantLive)))
    return;
end

liveIdentityFields = [ ...
    "RuntimeChannelLinkKey", "RuntimeChannelSeed", ...
    "RuntimeChannelStateContract", "GrantWorkerSafe", ...
    "GrantSharedStateCommitMode", "Frame", "Slot", "UEIndex", ...
    "ServingCell", "Direction"];
for fieldName = liveIdentityFields
    f = char(fieldName);
    if isfield(grantLive, f)
        grantOut.(f) = grantLive.(f);
    end
end

% These values describe the current PUSCH occasion, never the immutable
% transport block.  Copy the live value when present and otherwise clear a
% stale cached value with a type-correct empty default.
occasionDefaults = struct( ...
    "ExpectedUCIBits", int8([]), ...
    "MultiplexedUCIBits", int8([]), ...
    "HARQACKBits", int8([]), ...
    "MultiplexedHARQACKBits", int8([]), ...
    "UCIOnPUSCHApplied", false, ...
    "UCIOnPUSCHSource", "", ...
    "PUCCHCollisionPolicy", "", ...
    "PUCCHSourceSlot", NaN, ...
    "PUCCHGrantId", "", ...
    "UCIOnPUSCHFeedbackGrantIds", "", ...
    "UCIOnPUSCHFeedbackSourceSlots", [], ...
    "UCIOnPUSCHFeedbackHARQIds", [], ...
    "UCIOnPUSCHFeedbackBitCount", 0, ...
    "UCIOnPUSCHEvidenceSource", "");
occasionFields = string(fieldnames(occasionDefaults));
for fieldName = occasionFields.'
    f = char(fieldName);
    if isfield(grantLive, f)
        grantOut.(f) = grantLive.(f);
    elseif isfield(grantOut, f)
        grantOut.(f) = occasionDefaults.(f);
    end
end
end
