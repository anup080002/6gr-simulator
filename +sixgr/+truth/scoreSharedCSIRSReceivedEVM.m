function out=scoreSharedCSIRSReceivedEVM(item,reception,desired,source,replay,owner)
% Original emitted aggregate receive error, independent of optional models.
% Post-receiver native operator replay only; no channel/RF/random execution.
out=struct('Metrics',struct('Available',false, ...
    'Status',"unavailable_original_received_CSI_binding"),'Pairs',struct([]));
if nargin==0, return; end
try
    id='sixgr:truth:CSIRSReceivedEVMIdentity';
    assert(isa(owner,'sixgr.truth.CoupledWaveformStream')&&string(item.Kind)=="CSIRS",id, ...
        'Use the original completed CSI owner.');
    p=item.Context.Prepared; c=p.Carrier;
    assert(string(p.ExecutionStage)=="csirs_waveform_prepared_not_received"&& ...
        owner.Events.NextSampleIndex>=p.ReceiveEndSampleExclusive&& ...
        isequal(reception.PhysicalMeasurementDemodulationReceiptAvailable,true),id, ...
        'The original practical measurement must complete before receive-error scoring.');
    token=string(reception.PhysicalMeasurementDemodulationReceiptJSON);
    assert(sha(token)==string(reception.PhysicalMeasurementDemodulationReceiptSHA256),id,'Original demodulation receipt changed.');
    r=jsondecode(token);
    assert(any(string(r.ContractVersion)==["sixgr.csirs.physical_demodulation/v1","sixgr.csirs.physical_demodulation/v2"])&& ...
        string(r.Source)=="original_CSI_RS_physical_measurement_demodulation"&& ...
        string(r.InputPlane)=="supplied_pre_composite_receiver_front_end_capture"&& ...
        string(r.InputHashSerialization)=="WaveformHash.runtimeArray_class_dimensions_real_imag_double"&& ...
        isequal(r.IndependentPowerReferenceAvailable,false)&&isequal(r.RSRPAccuracyQualified,false)&& ...
        isequal(r.WaveformAmplitudeUnitRecognized,true)&& ...
        any(string(r.WaveformAmplitudeUnit)==["sqrt_mW","normalized_complex_baseband"])&& ...
        r.AdditionalTimingAcquisitions==0&&r.AdditionalOFDMDemodulations==0,id, ...
        'Retain the original measurement plane and operator scope.');
    pre=plane(item,string(source.ReceiverID)+":pre_rf",p,true);
    tx=plane(item,string(item.Context.TransmitterPlane),p,false);
    target=plane(item,string(item.Context.DesiredReferencePlane),p,true);
    assert(target==desired&&string(source.Source)=="actual_executed_link_contribution"&& ...
        string(source.TransmitterID)+":tx"==string(item.Context.TransmitterPlane)&& ...
        string(source.ReceiverID)==string(replay.ReceiverID)&& ...
        source.StartSample==pre.StartSample&&source.EndSampleExclusive==pre.EndSampleExclusive&& ...
        isequal(source.ReceiverEstimatorInput,false)&&source.AdditionalRFExecutions==0&& ...
        source.AdditionalChannelExecutions==0&&pre.sampleHash()==string(r.InputSHA256)&& ...
        desired.NumReceiveAntennas==pre.NumReceiveAntennas&& ...
        isequal(double(r.InputSize(:).'),[pre.EndSampleExclusive-pre.StartSample pre.NumReceiveAntennas])&& ...
        string(r.WaveformAmplitudeUnit)==string(replay.WaveformAmplitudeUnit)&& ...
        string(r.WaveformAmplitudeUnit)==string(p.PowerContext.WaveformAmplitudeUnit),id, ...
        'Bind exact original endpoint samples, window and units.');
    element=sixgr.rf.validateReceiveElementObservation(pre,replay,owner.Physical.receiveElementLayout(string(source.ReceiverID)));
    assert(isequal(element.Available,true),id,'Original receive-element binding is required.');
    records=owner.CSIRSTransmissions;
    hit=find(string({records.ComponentID})==string(item.Context.ComponentID));
    assert(isscalar(hit),id,'One actual completed CSI transmission owns the reference.');
    x=records(hit); maps=p.Tx.CSIRSRuntimeEvent.ResourceEvents; resources=p.Tx.CSIRSInfo.Resources;
    recorded=r.Resources; if iscell(recorded), recorded=vertcat(recorded{:}); end
    assert(string(x.SignalFamily)=="CSI-RS"&&x.ServingCell==item.Context.ServingCell&& ...
        x.Slot==item.Context.Slot&&x.TransmitStartSample==tx.StartSample&& ...
        x.EndSampleExclusive==tx.EndSampleExclusive&&x.CommittedAtSample==tx.EndSampleExclusive&& ...
        x.SampleRateHz==p.SampleRateHz&&x.PhysicalConfigurationEpoch==owner.Physical.ConfigurationEpoch&& ...
        string(x.TransmitterID)==string(source.TransmitterID)&& ...
        string(x.TransmitObservationSHA256)==tx.sampleHash()&&x.ResourceSetID==r.ResourceSetID&& ...
        x.TXAmplitudeScale==p.PowerContext.AmplitudeScale&& ...
        numel(x.ExecutedResourceMaps)==numel(maps)&&numel(maps)==numel(resources)&& ...
        numel(resources)==numel(recorded),id,'Bind the actual transmitted resource population, not queued intent.');
    for name=["NSizeGrid","NStartGrid","SubcarrierSpacing","NSlot","NFrame"]
        assert(isnumeric(x.CarrierIdentity.(name))&&isnumeric(c.(name))&& ...
            isequal(double(x.CarrierIdentity.(name)),double(c.(name))),id,'Original transmitted carrier changed.');
    end
    assert(string(x.CarrierIdentity.CyclicPrefix)==string(c.CyclicPrefix),id,'Original transmitted CP changed.');
    q=owner.Events.originalEnqueueReceipt(source.TransmitterID,item.Context.ComponentID);
    assert(q.StartSample==p.TransmitStartSample&&q.EndSampleExclusive==p.TransmitStartSample+p.NumSamples&& ...
        q.SampleRateHz==p.SampleRateHz&&string(q.OriginalSampleSHA256)==numericHash(p.TransmitSamples),id, ...
        'Do not transplant or regenerate the original parent waveform.');
    supports=cell(numel(resources),1); K=12*double(c.NSizeGrid); L=double(c.SymbolsPerSlot);
    for k=1:numel(resources)
        m=maps(k); z=x.ExecutedResourceMaps(k); resource=resources(k); native=recorded(k);
        for name=["ResourceID","LogicalPortCount","WaveformPrecoderDigest", ...
                "WaveformPrecoderMatrix","WaveformIndices","WaveformSymbols"]
            assert(isequaln(z.(name),m.(name)),id,'Executed CSI resource mapping changed.');
        end
        assert(isequaln(z.LogicalPilotIndices,resource.Indices)&& ...
            isequaln(z.LogicalPilotSymbols,resource.Symbols)&& ...
            native.ResourceID==resource.ResourceID&&native.ResourceOrdinal0==k-1, ...
            id,'Preserve original logical reference and physical resource identity.');
        index=double(resource.Indices(:));
        assert(all(index>=1&index<=K*L*m.LogicalPortCount&index==fix(index)),id,'Original pilot indices exceed the carrier.');
        base=unique(mod(index-1,K*L),'sorted'); supports{k}=[mod(base,K) floor(base/K)];
        assert(hash(supports{k})==string(native.PhysicalSupportSHA256)&& ...
            size(supports{k},1)==native.PhysicalRECount,id,'Original physical resource support changed.');
    end
    support=unique(vertcat(supports{:}),'rows','sorted');
    [f,hz,probeAccounting]=sixgr.truth.validateCSIRSOriginalOperator(r,reception,p,support);
    [Y,alignedHash]=sixgr.truth.applyCSIRSOriginalOperator(pre.readComplete(),c,r,hz);
    assert(alignedHash==string(r.AlignedSHA256)&&numericHash(Y)==string(r.GridSHA256),id, ...
        'Original noisy native operator replay must reproduce the actual receiver grid.');
    [D,~]=sixgr.truth.applyCSIRSOriginalOperator(desired.readComplete(),c,r,hz);
    request=struct('TransmitterID',string(source.TransmitterID),'ReceiverID',string(source.ReceiverID), ...
        'LinkID',string(source.LinkID),'ComponentID',string(item.Context.ComponentID), ...
        'ComponentSHA256',numericHash(p.TransmitSamples),'SampleRateHz',p.SampleRateHz, ...
        'ConfigurationEpoch',owner.Physical.ConfigurationEpoch,'FFTIntervals',double(f.FFTIntervals)+pre.StartSample);
    context=struct('ObservationID',string(item.ID),'ParentComponentID',string(item.Context.ComponentID), ...
        'StartSample',pre.StartSample,'EndSampleExclusive',pre.EndSampleExclusive,'SampleRateHz',p.SampleRateHz, ...
        'ConfigurationEpoch',owner.Physical.ConfigurationEpoch,'OriginalDemodulationReceiptSHA256',sha(token), ...
        'OriginalNoisyGridSHA256',numericHash(Y),'DesiredGridSHA256',numericHash(D), ...
        'WaveformAmplitudeUnit',string(r.WaveformAmplitudeUnit));
    [out.Metrics,out.Pairs]=sixgr.truth.pairCSIRSReceivedAggregate(Y,D,support,context,owner.Events.ExecutionTrace,request);
    out.Metrics.IsolatedCapabilityProbeDemodulations=probeAccounting.IsolatedProbeDemodulationsThisCall;
    out.Metrics.CapabilityProbeCacheHit=probeAccounting.CacheHit;
    out.Metrics.AdditionalOFDMDemodulations=2; out.Metrics.AdditionalRFExecutions=0;
    out.Metrics.AdditionalChannelExecutions=0; out.Metrics.OriginalEnqueueReceiptSHA256=string(q.ReceiptSHA256);
catch cause
    out.Metrics.Available=false; out.Metrics.Status="unavailable_original_received_CSI_binding_failed";
    out.Metrics.ErrorIdentifier=string(cause.identifier); out.Metrics.ErrorMessage=string(cause.message);
    out.Pairs=struct([]);
end
end

function b=plane(item,name,p,isReceive)
hit=find(string({item.Planes.ReceiverID})==name);
assert(isscalar(hit),'sixgr:truth:CSIRSReceivedEVMIdentity','One original observation plane required.');
b=item.Planes(hit).Observation;
if isReceive, first=p.ReceiveStartSample; stop=p.ReceiveEndSampleExclusive;
else, first=p.TransmitStartSample; stop=first+p.NumSamples; end
assert(isa(b,'sixgr.phy.waveform.WaveformObservationBuffer')&&isscalar(b)&&b.isComplete()&& ...
    b.SampleRateHz==p.SampleRateHz&&b.StartSample==first&&b.EndSampleExclusive==stop, ...
    'sixgr:truth:CSIRSReceivedEVMIdentity','Preserve the exact original completed window.');
end
function value=sha(token), value=string(sixgr.util.sha256Hex(char(token))); end
function value=hash(x), value=sixgr.phy.waveform.WaveformHash.runtimeArray(x); end
function value=numericHash(x), value=sixgr.phy.waveform.WaveformHash.numeric(x); end
