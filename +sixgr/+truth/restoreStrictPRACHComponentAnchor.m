function result = restoreStrictPRACHComponentAnchor(anchorRoot, scenarioID, configHash)
%RESTORESTRICTPRACHCOMPONENTANCHOR Restore a completed, identity-bound anchor.
%   This is a resumable-finalization adapter, not a simulation fallback. It
%   accepts only a same-run component anchor whose identity, manifest bytes,
%   hashes, strict verdict, statistical qualification and trial truth flags
%   all validate. Any discrepancy fails closed.

anchorRoot = string(anchorRoot);
scenarioID = strtrim(string(scenarioID));
configHash = lower(strtrim(string(configHash)));
if ~isscalar(scenarioID) || strlength(scenarioID) == 0 || ...
        ~isscalar(configHash) || strlength(configHash) ~= 64
    error("sixgr:truth:prachResume:ExpectedIdentityInvalid", ...
        "PRACH resume requires scalar ScenarioID and 64-character ConfigHash values.");
end
if ~isfolder(anchorRoot)
    error("sixgr:truth:prachResume:AnchorMissing", ...
        "Strict PRACH anchor folder is missing: %s", char(anchorRoot));
end

identityPath = fullfile(anchorRoot, "component_anchor_identity.json");
summaryPath = fullfile(anchorRoot, "reports", "json", ...
    "prach_conformance_summary.json");
manifestPath = fullfile(anchorRoot, "control", "csv", ...
    "prach_strict_artifact_manifest.csv");
localRequireFile(identityPath, "AnchorIdentityMissing");
localRequireFile(summaryPath, "ConformanceSummaryMissing");
localRequireFile(manifestPath, "ArtifactManifestMissing");

identity = jsondecode(fileread(identityPath));
if string(sixgr.util.structGet(identity, "SchemaName", "")) ~= ...
        "sixgr.component_anchor_identity" || ...
        string(sixgr.util.structGet(identity, "SchemaVersion", "")) ~= "1.0.0" || ...
        lower(strtrim(string(sixgr.util.structGet(identity, "Component", "")))) ~= "prach" || ...
        strtrim(string(sixgr.util.structGet(identity, "ParentScenarioID", ""))) ~= scenarioID || ...
        lower(strtrim(string(sixgr.util.structGet(identity, "ParentConfigHash", "")))) ~= configHash
    error("sixgr:truth:prachResume:AnchorIdentityMismatch", ...
        "Persisted PRACH anchor identity does not match scenario %s / config %s.", ...
        scenarioID, configHash);
end

manifest = readtable(manifestPath, "Delimiter", ",", ...
    "VariableNamingRule", "preserve", "TextType", "string");
requiredColumns = ["ArtifactId", "FilePath", "ByteCount", "SHA256"];
if isempty(manifest) || ~all(ismember(requiredColumns, ...
        string(manifest.Properties.VariableNames)))
    error("sixgr:truth:prachResume:ArtifactManifestInvalid", ...
        "Strict PRACH artifact manifest is empty or lacks required columns.");
end
requiredArtifacts = ["prach_config_strict.csv", "prach_strict_trials.csv"];
if ~all(ismember(requiredArtifacts, string(manifest.ArtifactId)))
    error("sixgr:truth:prachResume:ArtifactManifestIncomplete", ...
        "Strict PRACH manifest lacks its configuration or trial evidence.");
end
normalizedRoot = localNormalizedExistingPath(anchorRoot) + "/";
normalizedManifestPath = localNormalizedExistingPath(manifestPath);
selfRows = false(height(manifest), 1);
for rowIndex = 1:height(manifest)
    artifactPath = string(manifest.FilePath(rowIndex));
    localRequireFile(artifactPath, "ArtifactMissing");
    normalizedPath = localNormalizedExistingPath(artifactPath);
    if ~startsWith(lower(normalizedPath), lower(normalizedRoot))
        error("sixgr:truth:prachResume:ArtifactOutsideAnchor", ...
            "Manifest artifact is outside the PRACH anchor: %s", artifactPath);
    end
    selfRows(rowIndex) = lower(normalizedPath) == lower(normalizedManifestPath);
    if selfRows(rowIndex)
        if string(manifest.ArtifactId(rowIndex)) ~= "prach_strict_artifact_manifest.csv"
            error("sixgr:truth:prachResume:ArtifactManifestInvalid", ...
                "The manifest self-row has an unexpected ArtifactId: %s", ...
                string(manifest.ArtifactId(rowIndex)));
        end
        continue;
    end
    info = dir(artifactPath);
    if isempty(info) || double(info.bytes) ~= double(manifest.ByteCount(rowIndex))
        error("sixgr:truth:prachResume:ArtifactByteCountMismatch", ...
            "PRACH artifact byte count changed: %s", artifactPath);
    end
    observedHash = sixgr.protocol.ProtocolHash.file(artifactPath);
    if observedHash ~= lower(strtrim(string(manifest.SHA256(rowIndex))))
        error("sixgr:truth:prachResume:ArtifactHashMismatch", ...
            "PRACH artifact SHA-256 changed: %s", artifactPath);
    end
end
if nnz(selfRows) > 1
    error("sixgr:truth:prachResume:ArtifactManifestInvalid", ...
        "Strict PRACH artifact manifest contains more than one self-reference.");
end

summary = jsondecode(fileread(summaryPath));
if ~logical(sixgr.util.structGet(summary, "StrictOk", false)) || ...
        ~logical(sixgr.util.structGet(summary, "StatisticallyQualified", false)) || ...
        upper(strtrim(string(sixgr.util.structGet(summary, ...
        "StatisticalQualification", "")))) ~= "PASS"
    error("sixgr:truth:prachResume:StrictQualificationMissing", ...
        "Persisted PRACH evidence is not strictly and statistically qualified.");
end

trialPath = fullfile(anchorRoot, "control", "csv", "prach_strict_trials.csv");
configPath = fullfile(anchorRoot, "control", "csv", "prach_config_strict.csv");
summarySourcePath = string(sixgr.util.structGet(summary, "source_csv", ""));
summarySourceHash = lower(strtrim(string(sixgr.util.structGet(summary, ...
    "source_csv_sha256", ""))));
if strlength(summarySourcePath) == 0 || ~isfile(summarySourcePath) || ...
        localNormalizedExistingPath(summarySourcePath) ~= ...
        localNormalizedExistingPath(trialPath) || ...
        strlength(summarySourceHash) ~= 64 || ...
        sixgr.protocol.ProtocolHash.file(summarySourcePath) ~= summarySourceHash
    error("sixgr:truth:prachResume:ConformanceSourceMismatch", ...
        "PRACH conformance summary is not hash-bound to the anchor trial CSV.");
end
trialTable = readtable(trialPath, "Delimiter", ",", ...
    "VariableNamingRule", "preserve", "TextType", "string");
configTable = readtable(configPath, "Delimiter", ",", ...
    "VariableNamingRule", "preserve", "TextType", "string");
if isempty(trialTable) || isempty(configTable)
    error("sixgr:truth:prachResume:RequiredTableEmpty", ...
        "Persisted strict PRACH configuration/trial tables must be nonempty.");
end
localRequireFalse(trialTable, "ProxyUsed");
localRequireFalse(trialTable, "Skipped");
localRequireFalse(trialTable, "ToolboxMissing");
prachConfigHash = lower(strtrim(string(sixgr.util.structGet(summary, ...
    "ConfigHash", ""))));
if strlength(prachConfigHash) ~= 64
    error("sixgr:truth:prachResume:ConformanceConfigHashMissing", ...
        "PRACH conformance summary lacks its 64-character component ConfigHash.");
end
localValidateTrialSemantics(trialTable, scenarioID, prachConfigHash);

result = struct( ...
    "RunId", scenarioID, ...
    "ScenarioName", scenarioID, ...
    "StrictOk", true, ...
    "Ok", true, ...
    "StatisticallyQualified", true, ...
    "StatisticalQualification", "PASS", ...
    "FailureReason", "", ...
    "ProxyUsed", false, ...
    "Skipped", false, ...
    "ToolboxMissing", false, ...
    "UsedOracleFields", "", ...
    "DetectionSummary", summary, ...
    "ArtifactTables", struct( ...
        "prach_config_strict", configTable, ...
        "prach_trials", trialTable), ...
    "ArtifactManifest", manifest, ...
    "RestoredFromPersistedCompletedSupplementalEvidence", true, ...
    "RestorationAuthority", "identity_bound_manifest_hash_verified", ...
    "LegacySelfReferentialManifestRowIgnored", any(selfRows), ...
    "EvidenceScope", "component_anchor", ...
    "ArtifactRoot", anchorRoot);
end

function localRequireFile(pathValue, code)
if ~isfile(pathValue)
    error(char("sixgr:truth:prachResume:" + string(code)), ...
        "Required strict PRACH evidence file is missing: %s", char(pathValue));
end
end

function localRequireFalse(T, name)
if ismember(name, string(T.Properties.VariableNames)) && ...
        any(localLogical(T.(char(name))))
    error("sixgr:truth:prachResume:NonTruthTrialPresent", ...
        "Persisted strict PRACH trials contain %s=true.", name);
end
end

function localValidateTrialSemantics(T, scenarioID, prachConfigHash)
requiredColumns = ["TrialType", "StrictOk", "NegativeExpectedOk", ...
    "ConfigHash", "RunId", "Status"];
if ~all(ismember(requiredColumns, string(T.Properties.VariableNames)))
    error("sixgr:truth:prachResume:TrialSchemaInvalid", ...
        "Persisted strict PRACH trials lack required semantic columns.");
end
trialTypes = lower(strtrim(string(T.TrialType)));
requiredTypes = ["positive_high_snr", "missed_detection_sweep", ...
    "false_alarm_sweep", "negative_wrong_root"];
if ~all(ismember(requiredTypes, unique(trialTypes)))
    error("sixgr:truth:prachResume:TrialCoverageIncomplete", ...
        "Persisted strict PRACH trials lack a required trial family.");
end
positiveRows = trialTypes == "positive_high_snr";
negativeRows = trialTypes == "negative_wrong_root";
if ~all(localLogical(T.StrictOk(positiveRows))) || ...
        ~all(localLogical(T.NegativeExpectedOk(negativeRows))) || ...
        any(upper(strtrim(string(T.Status))) == "ERROR")
    error("sixgr:truth:prachResume:TrialFailurePresent", ...
        "Persisted strict PRACH positive/negative semantic guards failed.");
end
if any(strtrim(string(T.RunId)) ~= scenarioID) || ...
        any(lower(strtrim(string(T.ConfigHash))) ~= prachConfigHash)
    error("sixgr:truth:prachResume:TrialIdentityMismatch", ...
        "Persisted strict PRACH trial identity differs from its parent anchor.");
end
end

function value = localLogical(raw)
if islogical(raw)
    value = raw(:);
elseif isnumeric(raw)
    value = isfinite(double(raw(:))) & double(raw(:)) ~= 0;
else
    value = ismember(lower(strtrim(string(raw(:)))), ...
        ["true", "1", "yes", "pass", "ok"]);
end
end

function value = localNormalizedExistingPath(pathValue)
[ok, attributes] = fileattrib(char(string(pathValue)));
if ~ok
    error("sixgr:truth:prachResume:ArtifactMissing", ...
        "Unable to resolve strict PRACH evidence path: %s", char(string(pathValue)));
end
value = strip(replace(string(attributes.Name), "\", "/"), "right", "/");
end
