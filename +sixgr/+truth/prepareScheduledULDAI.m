function grant=prepareScheduledULDAI(ledger,cfg,grant)
% Finalize ordinary DCI 0_1 total DAI from accepted DL scheduling state.
% This is gNB control-plane knowledge, not decoded UE feedback or a TX count.
policy=sixgr.util.structGet(cfg,'phy.pdcch.operatorControl.connected_dci',struct());
if upper(string(grant.Direction))~="UL" || isempty(fieldnames(policy)), return; end
sixgr.phy.pdcch.ConnectedDCIProfile.validatePolicy(policy);
sixgr.phy.grant.assertGrantTimingIdentity(grant,'UL');
t=grant.TimingDecision;
assert(isequal(t.Valid,true) && ...
    sixgr.phy.pdcch.normalizeDCIFormat(grant.DCI.Format)=="0_1" && ...
    grant.PHYGrant.CodingLayout.NumCodewords==1, ...
    'sixgr:truth:UnsupportedScheduledULDAIPolicy', ...
    'Ordinary UL total DAI requires a valid single-codeword DCI 0_1 grant.');
context=sixgr.phy.pdcch.DCIContext(grant.DCI.ContextData);
installed=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,'0_1');
assert(context.Digest==installed.Digest && context.Data.RNTIValue==grant.RNTI && ...
    context.Data.DAIWidth==2,'sixgr:truth:ScheduledULDAIContextMismatch', ...
    'UL scheduling must use the exact installed two-bit DAI context.');
if isempty(ledger) || (isstruct(ledger) && isscalar(ledger) && isempty(fieldnames(ledger)))
    ledger=struct('Version',1,'LastControlAbsoluteSlot',-1,'Entries',struct([]));
end
assert(isstruct(ledger) && isscalar(ledger) && all(isfield(ledger, ...
    {'Version','LastControlAbsoluteSlot','Entries'})) && ledger.Version==1 && ...
    isstruct(ledger.Entries),'sixgr:truth:InvalidDAILedger', ...
    'Use the accepted, versioned DL scheduling ledger.');
assert(ledger.LastControlAbsoluteSlot<=t.ControlAbsoluteSlot, ...
    'sixgr:truth:FutureScheduledULDAI','UL DCI cannot borrow future DL scheduling state.');
group=struct([]); keys=zeros(0,2);
for entry=ledger.Entries(:).'
    a=entry.Assignment;
    assert(entry.AssignmentDigest==sixgr.phy.pucch.PUCCHUtil.hash(a) && ...
        entry.Source=="gnb_scheduled_type2_counter_not_ue_reception", ...
        'sixgr:truth:InvalidDAILedger','Scheduled assignment integrity/source differs.');
    if a.RNTI~=grant.RNTI || a.PhysicalServingCell~=grant.ServingCell || ...
        a.ScheduledCCID~=string(t.ScheduledCCID) || ...
        a.ConfigurationEpoch~=context.Data.ConfigurationEpoch || ...
        a.FeedbackAbsoluteSlot~=t.DataAbsoluteSlot, continue; end
    assert(a.ControlAbsoluteSlot<t.ControlAbsoluteSlot || ...
        (a.ControlAbsoluteSlot==t.ControlAbsoluteSlot && ...
         a.ControlStartSymbol<=t.ControlSymbolAllocation(1)), ...
        'sixgr:truth:FutureScheduledULDAI','UL DAI cannot count a later monitoring occasion.');
    if isempty(group), group=entry; else, group(end+1)=entry; end %#ok<AGROW>
    keys(end+1,:)=[a.ControlAbsoluteSlot a.ControlStartSymbol]; %#ok<AGROW>
end
count=numel(group);
if count>0
    [keys,order]=sortrows(keys,[1 2]); group=group(order);
    assert(size(unique(keys,'rows'),1)==count && ...
        isequal([group.Ordinal],1:count) && ...
        isequal([group.RawDAI],mod((1:count)-1,4)) && ...
        isequal([group.CounterDAI],mod((1:count)-1,4)+1), ...
        'sixgr:truth:InvalidDAILedger','Accepted DL count has gaps, duplicates or changed DAI.');
end
raw=mod(count-1,4); % No DL assignments -> on-wire 11, semantic total DAI four.
old=sixgr.phy.pdcch.decodeDCIPayload(grant.DCI.Bits,'0_1',context);
fields=struct();
for definition=old.Schema.Definitions(:).'
    name=char(definition.Name); fields.(name)=old.Fields.(name);
end
fields.first_dai=raw;
packed=sixgr.phy.pdcch.encodeDCIPayload(fields,'0_1',context);
authority=struct('RNTI',grant.RNTI,'PhysicalServingCell',grant.ServingCell, ...
    'ScheduledCCID',string(t.ScheduledCCID),'ConfigurationEpoch',context.Data.ConfigurationEpoch, ...
    'ControlAbsoluteSlot',t.ControlAbsoluteSlot,'ControlStartSymbol',t.ControlSymbolAllocation(1), ...
    'PUSCHAbsoluteSlot',t.DataAbsoluteSlot,'ScheduledDLAssignmentCount',count, ...
    'RawDAI',raw,'TotalDAI',raw+1,'ScheduledDLAssignments',group, ...
    'Source',"gnb_accepted_dl_schedule_total_dai_not_ue_reception");
authority.Digest=sixgr.phy.pucch.PUCCHUtil.hash(authority);
grant.DAI=raw; grant.ULTotalDAIAuthority=authority;
grant.DCI.Bits=uint8(packed.Bits(:));
grant.DCI.Hex=char(packed.PayloadHex);
grant.DCI.PayloadHex=char(packed.PayloadHex);
grant.DCI.PayloadHash=char(packed.PayloadHash);
grant.DCI.FieldTable=packed.FieldTable;
grant.DCI.FieldValues.first_dai=raw;
grant.DCI.FieldValues.DAI=raw;
end
