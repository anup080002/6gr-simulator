function result=receiveSharedPUSCHWithoutTransmission(state,observationID)
% Decode a stream-owned gNB capture, without a prepared UE transmission.
% Current and combined CRC remain distinct. No UE TX scoring, known-TB EVM,
% BER, goodput or scheduler disposition is manufactured by this receiver.
owner=state.SharedWaveformStream;
assert(isa(owner,'sixgr.truth.CoupledWaveformStream') && isscalar(owner), ...
    'sixgr:truth:SharedUCIClockRequired','Use the actual shared physical owner.');
item=owner.readPUSCHReceiveOnlyCompletion(observationID);
grant=item.Context.Grant; cfg=item.Context.Config;
ids=string({item.Planes.ReceiverID});
postIndex=find(endsWith(ids,':post_rf')); preIndex=find(endsWith(ids,':pre_rf'));
assert(numel(ids)==2 && isscalar(postIndex) && isscalar(preIndex), ...
    'sixgr:truth:IncompletePUSCHReceiveOnlyPlanes','Require actual pre/post RF; never fabricate a transmitter plane.');
post=item.Planes(postIndex).Observation; pre=item.Planes(preIndex).Observation;
assert(post.isComplete() && pre.isComplete() && post.SampleRateHz==owner.SampleRateHz && ...
    pre.SampleRateHz==post.SampleRateHz && pre.StartSample==post.StartSample && ...
    pre.EndSampleExclusive==post.EndSampleExclusive && ...
    pre.NumReceiveAntennas==post.NumReceiveAntennas && ...
    post.EndSampleExclusive<=owner.Events.NextSampleIndex, ...
    'sixgr:truth:PUSCHHARQObservationClockMismatch','Receive only complete, same-clock, stream-owned samples.');
receiverID=extractBefore(ids(postIndex),':post_rf');
assert(extractBefore(ids(preIndex),':pre_rf')==receiverID, ...
    'sixgr:truth:PUSCHReceiveOnlyIdentityMismatch','Both planes must belong to the same gNB receiver.');
[observation,gain]=sixgr.phy.rx.compensateReceivedAGC( ...
    post,item.Planes(postIndex).Segments,receiverID);
binding=sixgr.truth.puschUCIObservationBinding(grant,observation);
[receiverAttempt,priorSoft]=sixgr.truth.prepareSharedULHARQReception(state,cfg,grant,observation);
[obligation,report]=sixgr.truth.resolveSharedPUSCHCSIReceiveObligation(state,cfg,grant);
[context,mapping]=sixgr.truth.buildSharedPUSCHUCIReceiveContext( ...
    state,cfg,grant,binding.ObservationID,obligation,report);
% Remove UE-owned optional fields, as on the normal independent receive path.
for name=["receivedDCIAssignment","receivedHARQState"]
    if isfield(cfg.phy.pusch,name), cfg.phy.pusch=rmfield(cfg.phy.pusch,name); end
end
sixgr.phy.grant.assertPHYGrantDimensions(grant.PHYGrant,'receive_only_pusch_decoder');
cfg=sixgr.phy.grant.applyPHYGrantToConfig(cfg,grant.PHYGrant);
carrier=sixgr.phy.grid.makeCarrier(cfg); info=nrOFDMInfo(carrier);
symbols=double(carrier.SymbolsPerSlot);
localSlot=mod(double(carrier.NSlot),double(carrier.SlotsPerSubframe));
count=sum(double(info.SymbolLengths(localSlot*symbols+(1:symbols))));
% Search is bounded by real capture coverage, not a generated waveform's
% length, UE timing advance, perfect channel delay, or zero-padding.
search=[0 observation.EndSampleExclusive-observation.StartSample-count];
validateattributes(search,{'numeric'},{'real','finite','integer','nonnegative','numel',2});
assert(observation.NumReceiveAntennas==grant.PHYGrant.AntennaArchitecture.NumRxAntennas, ...
    'sixgr:truth:PUSCHReceiveOnlyAntennaMismatch','The actual gNB branches must match its frozen receive allocation.');
assert(isfield(grant.HARQ,'IsRetransmission') && isscalar(grant.HARQ.IsRetransmission) && ...
    any(grant.HARQ.IsRetransmission==[0 1]), ...
    'sixgr:truth:PUSCHReceiveOnlyHARQAuthority','Retain the scheduled new-TB/retransmission status.');
initial=sixgr.link.resolvePUSCHUCIInitialMCS(cfg,grant,struct(), ...
    logical(grant.HARQ.IsRetransmission),grant.PHYGrant.CodingLayout.MCSIndex);
args={'PHYGrant',grant.PHYGrant,'UCIReceiveContext',context, ...
    'UCIReportConfiguration',report,'InitialIMCSPerCodeword',initial.MCS, ...
    'TimingSearchWindowSamples',search};
combiner=sixgr.util.structGet(grant,'MUMIMOReceiveCombiningMatrix', ...
    sixgr.util.structGet(grant.PHYGrant,'LegacyGrantSnapshot.MUMIMOReceiveCombiningMatrix',[]));
if ~isempty(combiner)
    digest=sixgr.util.structGet(grant,'MUMIMOReceiveCombiningMatrixSHA256', ...
        sixgr.util.structGet(grant.PHYGrant,'LegacyGrantSnapshot.MUMIMOReceiveCombiningMatrixSHA256',""));
    args=[args,{'ReceiveCombiningMatrix',combiner,'ReceiveCombiningMatrixSHA256',digest}];
end
% No injection variance, channel truth, transmitted UCI/TB, or prior UE
% soft buffer is passed. DM-RS estimates the actual received disturbance.
[rx,info]=sixgr.phy.ul.PUSCH_Rx(observation.readComplete(),cfg,args{:});
assert(islogical(rx.ULSCHDecodeAttempted) && isscalar(rx.ULSCHDecodeAttempted), ...
    'sixgr:truth:ULHARQDecodeAvailabilityRequired','Retain explicit scalar data-decode availability.');
decision=struct('ReceiverAttempt',receiverAttempt,'DecodeAttempted',rx.ULSCHDecodeAttempted, ...
    'CRCPass',false,'SoftBuffer',[]);
ul=struct('CurrentCRCAvailable',rx.ULSCHDecodeAttempted,'CurrentCRCPass',false, ...
    'CombinedDecodeAttempted',false,'CombinedCRCPass',false,'DecodedBits',int8([]), ...
    'CombiningApplied',false,'ReceiverKey',receiverAttempt.Attempt.ReceiverKey);
if rx.ULSCHDecodeAttempted
    current=sixgr.link.resolveULHARQReceiverOutcome(rx,[]);
    [combined,combination]=sixgr.phy.harq.combineSoftLLR(rx.RateRecoveredLLR,priorSoft, ...
        'CurrentLayout',rx.CodingLayout,'HARQKey',receiverAttempt.Attempt.ReceiverKey);
    final=current;
    if ~isempty(priorSoft) && ~current.CurrentDecodeOK
        [pass,~,bits]=sixgr.phy.harq.decodeCombinedULSCH(rx.CodingLayout,combined,cfg);
        final=sixgr.link.resolveULHARQReceiverOutcome(rx,struct('CRCPass',pass,'TransportBlock',bits));
        ul.CombinedDecodeAttempted=true;
        ul.CombinedCRCPass=pass;
    end
    ul.CurrentCRCPass=current.CurrentDecodeOK;
    ul.DecodedBits=final.DecodedTransportBlockBits;
    ul.CombiningApplied=combination.Applied;
    decision.CRCPass=final.CombinedDecodeOK;
    decision.SoftBuffer=combination.SoftBuffer;
end
observed=sixgr.truth.normalizeReceivedPUSCHHARQ(rx,context);
result=struct('ObservationID',string(observationID),'Binding',binding, ...
    'GrantSnapshot',grant,'UCIReceiveContext',context,'HARQMapping',mapping, ...
    'Receiver',rx,'ReceiverInfo',info,'IndependentHARQObservation',observed, ...
    'ULHARQReceiverDecision',decision,'ULHARQReceiverObservation',ul, ...
    'GainCompensation',gain,'Observation',observation, ...
    'CaptureCompletedAtSample',post.EndSampleExclusive, ...
    'ReceiverInvokedAtSample',owner.Events.NextSampleIndex, ...
    'DecodeScope',"gnb_current_observation_and_receiver_owned_soft_state_no_scheduler_commit", ...
    'Source',"stream_owned_gnb_capture_and_scheduled_grant_independent_receiver", ...
    'PreparedTransmitterConsumed',false,'OraclePayloadBitsUsed',false, ...
    'HARQStateCommitted',false);
end
