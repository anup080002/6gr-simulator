function evidence=collectCompletedCSIDataMapping(tx,projection,precoding)
%COLLECTCOMPLETEDCSIDATAMAPPING Check retained data symbols, not RF execution.
% This pure arithmetic boundary can also inspect declared component inputs.
% Only buildCompletedCSIApplicationEvidence joins it to actual TX/RX receipts.
% Native indices are authoritative; do not infer resource order from a PMI,
% flatten pages, average matrices, or manufacture a frozen per-PRG contract.
required={'PrecoderBundle','Carrier','PDSCHLayerSymbols','PDSCHPortSymbols', ...
    'PDSCHLayerIndices','PDSCHPortIndices','LayerSymbolOrder','PortSymbolOrder'};
assert(isstruct(tx) && isscalar(tx) && all(isfield(tx,required)) && ...
    isa(tx.PrecoderBundle,'sixgr.pdsch.PDSCHPrecoderBundle'), ...
    'sixgr:truth:CompletedCSIMatrixScope','Retain the native data arrays, indices and immutable bundle.');
b=tx.PrecoderBundle;
try
    gridSize=[double(tx.Carrier.NSizeGrid)*12,double(tx.Carrier.SymbolsPerSlot)];
catch
    error('sixgr:truth:CompletedCSIResourceMismatch','Retain explicit native carrier grid dimensions.');
end
assert(all(isfinite(gridSize) & gridSize>=1 & gridSize==fix(gridSize)), ...
    'sixgr:truth:CompletedCSIResourceMismatch','Native grid dimensions must be explicit positive integers.');
assert(isstruct(precoding) && isscalar(precoding) && ...
    all(isfield(precoding,{'WidebandOnly','MatrixPhysicalPorts'})) && isequal(precoding.WidebandOnly,true), ...
    'sixgr:truth:CompletedCSIFrozenPageContractRequired', ...
    'A genuinely varying frozen mapping needs a retained per-page grant contract; do not invent one here.');
assert(localFinite(projection) && ismatrix(projection) && ...
    size(projection,2)==b.NPhysicalTxAntennas && ...
    localFinite(precoding.MatrixPhysicalPorts) && ...
    isequal(size(precoding.MatrixPhysicalPorts),[size(projection,1),b.NLayerPorts]), ...
    'sixgr:truth:CompletedCSIMatrixMismatch','Projection and frozen physical matrix dimensions must agree.');
layers=tx.PDSCHLayerSymbols; ports=tx.PDSCHPortSymbols;
assert(localFinite(layers) && localFinite(ports) && ismatrix(layers) && ismatrix(ports) && ...
    size(layers,2)==b.NLayerPorts && size(ports,2)==b.NPhysicalTxAntennas && ...
    size(layers,1)==size(ports,1), ...
    'sixgr:truth:CompletedCSIMatrixMismatch','Retain every finite data symbol on every layer and port.');
[subcarrier,symbol]=localCoordinates(tx,tx.PDSCHLayerIndices,tx.LayerSymbolOrder,layers,"layer");
[portSubcarrier,portSymbol]=localCoordinates(tx,tx.PDSCHPortIndices,tx.PortSymbolOrder,ports,"port");
assert(isequal(subcarrier,portSubcarrier) && isequal(symbol,portSymbol), ...
    'sixgr:truth:CompletedCSIResourceMismatch','Layer and port arrays must address the same native resources in the same order.');
prb=floor((subcarrier-1)/12);
[expectedPorts,trace]=b.apply(double(layers).',prb,symbol-1,'Domain','data');
expectedPorts=expectedPorts.';
assert(localNear(double(ports),expectedPorts,1e-10), ...
    'sixgr:truth:CompletedCSIMatrixMismatch','Every retained port symbol must equal its selected native-resource page times the layers.');
if isfield(tx,'DataPrecoderTrace')
    assert(isequaln(tx.DataPrecoderTrace,trace), ...
        'sixgr:truth:CompletedCSIResourceMismatch','Retained producer selections must match the native coordinate selections.');
end
physicalPages=complex(zeros(size(projection,1),b.NLayerPorts,b.NPRG,b.NSymbolGroups));
pageSHA=strings(b.NPRG,b.NSymbolGroups); used=zeros(b.NPRG,b.NSymbolGroups);
physicalExpected=complex(zeros(size(layers,1),size(projection,1)));
for prg=1:b.NPRG
    for group=1:b.NSymbolGroups
        page=double(projection)*double(b.W(:,:,prg,group));
        physicalPages(:,:,prg,group)=page;
        pageSHA(prg,group)=string(sixgr.phy.mimo.MatrixContract.digest(page));
        selected=trace.PRG==prg-1 & trace.SymbolGroup==group-1;
        used(prg,group)=nnz(selected);
        if any(selected)
            assert(localNear(page,double(precoding.MatrixPhysicalPorts),1e-12), ...
                'sixgr:truth:CompletedCSIMatrixMismatch', ...
                'Every used page must match the actual frozen wideband matrix; unequal pages are not its application.');
            physicalExpected(selected,:)=double(layers(selected,:))*page.';
        end
    end
end
assert(localNear(double(ports)*double(projection).',physicalExpected,1e-10), ...
    'sixgr:truth:CompletedCSIMatrixMismatch','Check the actual physical-element data mapping for every resource.');
evidence=struct('ReferencePlane',"physical_element_data_grid_before_node_rf", ...
    'Source',"retained_native_data_indices_and_precoder_bundle_arithmetic", ...
    'ExecutionProof',false,'AdditionalPHYExecutions',0, ...
    'WaveformToElementMatrix',projection, ...
    'FrozenMappingContract',"frozen_wideband_matrix_checked_on_each_used_PRG_symbol_page", ...
    'FrozenMatrix',precoding.MatrixPhysicalPorts, ...
    'FrozenMatrixSHA256',string(sixgr.phy.mimo.MatrixContract.digest(double(precoding.MatrixPhysicalPorts))), ...
    'AppliedMatrixPages',physicalPages, ...
    'AppliedMatrixShape',[size(projection,1),b.NLayerPorts,b.NPRG,b.NSymbolGroups], ...
    'AppliedMatrixSHA256PerSlice',pageSHA,'DataResourcesPerSlice',used, ...
    'NativeBundleSHA256',b.ImmutableBundleDigest,'NativeMatrixSHA256PerSlice',b.MatrixDigestPerSlice, ...
    'NativeMatrixShape',b.MatrixShape,'NativeGridSubcarriers',gridSize(1),'NativeGridSymbols',gridSize(2), ...
    'DataLayerSymbolsSHA256',string(sixgr.phy.waveform.WaveformHash.runtimeArray(layers)), ...
    'DataPortSymbolsSHA256',string(sixgr.phy.waveform.WaveformHash.runtimeArray(ports)), ...
    'LayerIndicesSHA256',string(sixgr.phy.waveform.WaveformHash.runtimeArray(tx.PDSCHLayerIndices)), ...
    'PortIndicesSHA256',string(sixgr.phy.waveform.WaveformHash.runtimeArray(tx.PDSCHPortIndices)), ...
    'ResourceIndex0',trace.ResourceIndex,'SubcarrierIndex0',subcarrier-1, ...
    'OFDMSymbolIndex0',symbol-1,'PRBIndex0',prb,'PRGIndex0',trace.PRG, ...
    'SymbolGroupIndex0',trace.SymbolGroup, ...
    'PRBSet0',b.PRBSet,'ScheduledSymbols0',b.ScheduledSymbols, ...
    'SelectedIsOptimalClaimed',false,'RadiatedPowerClaimed',false);
end

function [subcarrier,symbol]=localCoordinates(tx,indices,order,values,domain)
assert(isnumeric(indices) && isreal(indices) && isequal(size(indices),size(values)) && ...
    all(isfinite(indices(:)) & indices(:)>=1 & indices(:)==fix(indices(:))) && ...
    numel(unique(indices(:)))==numel(indices), ...
    'sixgr:truth:CompletedCSIResourceMismatch','Require unique native one-based indices for every symbol cell.');
expected=sixgr.phy.resource.buildSymbolOrderingMap(tx.Carrier,indices,domain);
assert(isequaln(order,expected) && all(isfinite(expected.SubcarrierIndex(:))) && ...
    all(isfinite(expected.OFDMSymbolIndex(:))) && ...
    isequal(expected.PlaneIndex,repmat(1:size(values,2),size(values,1),1)), ...
    'sixgr:truth:CompletedCSIResourceMismatch','Native ordering must retain its exact carrier coordinates and plane columns.');
subcarrier=expected.SubcarrierIndex(:,1); symbol=expected.OFDMSymbolIndex(:,1);
assert(isequal(expected.SubcarrierIndex,repmat(subcarrier,1,size(values,2))) && ...
    isequal(expected.OFDMSymbolIndex,repmat(symbol,1,size(values,2))), ...
    'sixgr:truth:CompletedCSIResourceMismatch','Each row must contain the same resource on every layer or port.');
end

function tf=localFinite(value)
tf=isnumeric(value) && ~isempty(value) && all(isfinite(real(value(:))) & isfinite(imag(value(:))));
end

function tf=localNear(left,right,tolerance)
tf=isequal(size(left),size(right)) && norm(left-right,'fro')<=tolerance*max(1,norm(left,'fro'));
end
