function binding=bindReceivedPUCCHCodebookRows(book,rows)
% Match legacy producer bookkeeping to actual received UE events, not bits.
% The codebook owns transmitted bits, including protocol NACK gap positions.
% No gNB scheduling history may fill a missing event or alter its codebook.
assert(isa(book,'sixgr.phy.pucch.HARQACKCodebookState') && isscalar(book) && ...
    book.CodebookType=="TYPE2_DYNAMIC" && ~isempty(book.Events), ...
    'sixgr:truth:MissingReceivedPUCCHCodebook','Require a nonempty received Type-2 codebook.');
assert(istable(rows) && height(rows)==numel(book.Events) && ...
    all(ismember({'UEIndex','RNTI','SourceSlot','HarqID','ScheduledAbsoluteSlot'}, ...
    rows.Properties.VariableNames)), ...
    'sixgr:truth:ReceivedPUCCHProducerMismatch','Every received event needs one producer row.');
names={'UEIndex','RNTI','SourceSlot','HarqID','ScheduledAbsoluteSlot'};
keys=zeros(height(rows),numel(names));
for k=1:numel(names)
    raw=rows.(names{k});
    assert(isnumeric(raw) && isreal(raw) && iscolumn(raw) && ...
        all(isfinite(raw)) && all(raw==fix(raw)) && all(raw>=0), ...
        'sixgr:truth:ReceivedPUCCHProducerMismatch','Producer identities must be exact numeric scalars.');
    keys(:,k)=double(raw);
end
assert(size(unique(keys,'rows'),1)==height(rows), ...
    'sixgr:truth:ReceivedPUCCHProducerMismatch','Duplicate producer identities are not allowed.');
eventRows=zeros(numel(book.Events),1);
for k=1:numel(book.Events)
    e=book.Events(k).Data;
    assert(all(isfield(e,{'UEId','RNTI','DataAbsoluteSlot','HARQProcess','TargetSlot', ...
        'PUCCHResourceIndicator','ConfigurationEpoch'})) && ...
        e.ConfigurationEpoch==book.ConfigurationEpoch, ...
        'sixgr:truth:ReceivedPUCCHProducerMismatch','Retain the complete received event identity.');
    key=[e.UEId e.RNTI e.DataAbsoluteSlot+1 e.HARQProcess e.TargetSlot];
    hit=find(all(keys==key,2));
    assert(isscalar(hit),'sixgr:truth:ReceivedPUCCHProducerMismatch', ...
        'A received event must bind exactly one producer row without using its ACK value.');
    eventRows(k)=hit;
end
assert(numel(unique(eventRows))==height(rows), ...
    'sixgr:truth:ReceivedPUCCHProducerMismatch','Do not duplicate or omit a received event.');
binding=struct('EventRowIndices',eventRows,'LastRowIndex',eventRows(end), ...
    'BitCount',numel(book.Bits),'CodebookDigest',book.Digest, ...
    'Source',"received_UE_event_identity_not_pending_row_bit_order");
end
