function h=buildConfiguredPUCCHReception(state,cfg,ue,slot,observationID)
% No-HARQ receiver: eligible CSI, otherwise an installed standalone SR.
% UE pending bits, report tables and transmitter preparations are not inputs.
assert(isempty(sixgr.truth.scheduledHARQExpectationsForOccasion(state,ue,slot)), ...
    'sixgr:truth:CombinedHARQCSIReceptionRequired','Preserve scheduled HARQ ownership.');
id=cfg.phy.frame.DefaultIdentity; cellID=state.CurrentServingIdx(ue);
identity=struct('UEID',ue,'RNTI',state.MultiUser.RNTIStart+ue-1, ...
    'ServingCell',cellID,'PUCCHCell',cellID,'ComponentCarrier',id.ScheduledCCID, ...
    'ActiveULBWP',id.ULBWPID);
h=[];
if logical(sixgr.util.structGet(cfg,'phy.csi.reportCSI',false)) && ...
        string(sixgr.util.structGet(cfg,'phy.csi.reportTrigger',""))=="periodic"
    calendar=sixgr.truth.configuredCSIReportCalendar(cfg,identity,slot);
    [eligible,~]=sixgr.truth.resolveCSIReceiveReferenceEvidence(state,cfg,ue,cellID,calendar,slot);
    if height(calendar)==1 && calendar.ULResourceAvailable && eligible
        h=sixgr.truth.buildConfiguredPUCCHCSIReception(state,cfg,ue,slot,observationID);
        return;
    end
end
rrc=sixgr.phy.pucch.PUCCHConfigBuilder.receiverConfiguration(cfg,identity);
if isempty(rrc.Data.SchedulingRequestResources), return; end
calendar=sixgr.truth.buildConfiguredSRCalendar(cfg,identity,slot,slot);
calendar=calendar(calendar.ULResourceAvailable,:);
if isempty(calendar), return; end
assert(height(calendar)==1,'sixgr:truth:MultipleStandaloneSROccasions', ...
    'Multiple standalone SR resources require independently bound receive windows.');
resource=rrc.resourceByID(calendar.PUCCHResourceID);
context=sixgr.truth.buildConfiguredPUCCHReceiveContext(struct( ...
    'ObservationID',string(observationID),'ConfigurationEpoch',rrc.ConfigurationEpoch, ...
    'HARQBitCount',0,'SRBitCount',1,'PriorityIndex',calendar.PriorityIndex, ...
    'CSIReportConfigID',"",'CSIConfigurationEpoch',NaN));
timing="received_PUCCH_DMRS";
if resource.Format==0, timing="received_UL_clock_or_configured_SR_sequence_acquisition"; end
assignment=sixgr.phy.pucch.PUCCHReceptionAssignment(struct( ...
    'ObservationID',string(observationID),'ResourceID',resource.ID,'RNTI',identity.RNTI, ...
    'AbsoluteSlot0',slot-1,'Source',"installed_standalone_SR_calendar", ...
    'TimingSource',timing,'ResourceSelectionProcedure',"configured_sr"),rrc,context);
h=struct('SelectedTransport',"PUCCH",'Mapping',struct([]), ...
    'UEIndex',ue,'RNTI',identity.RNTI,'TargetSlot',slot,'ServingCell',cellID, ...
    'Assignment',assignment,'Context',context,'SRReportCalendar',calendar, ...
    'CSIReportConfiguration',[],'CSIReportCalendar',table(), ...
    'TransportScheduleEvidence',struct(),'Source',"installed_SR_occasion_not_UE_pending_state");
end
