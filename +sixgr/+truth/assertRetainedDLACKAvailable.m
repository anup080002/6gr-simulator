function assertRetainedDLACKAvailable(row,encodingSample,sampleRateHz)
% Protocol clock lineage is distinct from current PDSCH receive measurements.
% This gate proves decision availability, not a full N1 or TAG qualification.
if istable(row), assert(height(row)==1); row=table2struct(row); end
if ~isfield(row,'DueSlot') && isfield(row,'ScheduledAbsoluteSlot')
    row.DueSlot=row.ScheduledAbsoluteSlot;
end
try
    e=jsondecode(row.HARQProtocolDecisionEvidenceJSON);
catch
    error('sixgr:truth:InvalidRetainedACKTiming','Malformed retained-ACK evidence.');
end
required={'ContractVersion','UEId','RNTI','HARQProcess','NDI','ControlAbsoluteSlot', ...
    'DataAbsoluteSlot','ReceivedAssignmentDigest','PriorAcknowledgedAssignmentDigest', ...
    'PriorAcknowledgedDataAbsoluteSlot','InitialAssignmentDigest','RetainedTBSBits', ...
    'ACK','DecodeAttempted','DeliverTransportBlock','FeedbackTransmissionQualified', ...
    'Source','ControlAvailableAtSample','DecisionAvailableAtSample','SampleRateHz', ...
    'HARQFeedbackAbsoluteSlot','PUCCHResourceIndicator'};
assert(isstruct(e) && isscalar(e) && all(isfield(e,required)) && ...
    all(isfield(row,{'UEIndex','RNTI','HarqID','SourceSlot','DueSlot','PRIValue','TBSBits'})), ...
    'sixgr:truth:InvalidRetainedACKTiming','Retain the complete protocol/reservation identity.');
numbers=[e.ControlAbsoluteSlot e.DataAbsoluteSlot e.PriorAcknowledgedDataAbsoluteSlot ...
    e.ControlAvailableAtSample e.DecisionAvailableAtSample e.HARQFeedbackAbsoluteSlot];
assert(isnumeric(numbers) && isreal(numbers) && numel(numbers)==6 && ...
    all(isfinite(numbers)) && all(numbers>=0) && all(numbers==fix(numbers)) && ...
    string(e.ContractVersion)=="received_dl_retained_ack/v1" && ...
    string(e.Source)=="received_dci_and_ue_retained_decoded_tb" && ...
    isequal(e.ACK,true) && isequal(e.DecodeAttempted,false) && ...
    isequal(e.DeliverTransportBlock,false) && isequal(e.FeedbackTransmissionQualified,false) && ...
    e.RNTI==row.RNTI && e.UEId==row.UEIndex && e.HARQProcess==row.HarqID && ...
    e.DataAbsoluteSlot==row.SourceSlot-1 && ...
    e.HARQFeedbackAbsoluteSlot==row.DueSlot-1 && ...
    e.PUCCHResourceIndicator==row.PRIValue && e.RetainedTBSBits==row.TBSBits && ...
    e.PriorAcknowledgedDataAbsoluteSlot<e.DataAbsoluteSlot && ...
    e.ControlAbsoluteSlot<=e.DataAbsoluteSlot && ...
    e.ControlAvailableAtSample<=e.DecisionAvailableAtSample && ...
    e.SampleRateHz==sampleRateHz && ...
    all(strlength(string({e.ReceivedAssignmentDigest,e.PriorAcknowledgedAssignmentDigest, ...
        e.InitialAssignmentDigest}))==64), ...
    'sixgr:truth:InvalidRetainedACKTiming','Protocol identity and sample-clock lineage must agree.');
f=sixgr.truth.copyHARQReceiveTimingFields(row);
ack=[];
for name=["Ack","ExpectedAck","AckBit"]
    if isfield(row,name), ack=row.(name); break; end
end
assert(isscalar(ack) && (isnumeric(ack) || islogical(ack)) && double(ack)==1 && ...
    (~isfield(row,'NDI') || isequal(double(row.NDI),double(e.NDI))) && ...
    (~isfield(row,'CurrentDecodeOK') || isequal(logical(row.CurrentDecodeOK),false)) && ...
    (~isfield(row,'CombinedDecodeOK') || isequal(logical(row.CombinedDecodeOK),false)), ...
    'sixgr:truth:RetainedACKDecisionMismatch','The feedback bit must retain ACK without a new decode verdict.');
assert(strlength(string(f.DataReceiveTimingEvidenceJSON))==0 && ...
    all(isnan([f.DataReceiveSymbolStartSample f.DataReceiveSymbolEndSampleExclusive ...
    f.DataDecodeAvailableAtSample f.DataReceiveSampleRateHz])) && ...
    strlength(string(f.DataReceiveTimingSource))==0, ...
    'sixgr:truth:RetainedACKClaimedCurrentDecode','A protocol ACK must not claim a current data decode or timing estimate.');
assert(e.DecisionAvailableAtSample<=encodingSample, ...
    'sixgr:truth:FutureHARQFeedbackAtUCIEncoding','The retained-ACK decision is not available at this encoding event.');
end
