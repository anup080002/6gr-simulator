function [completionSlot0,blockedSlotCount]=resolveRAAttachCompletion(result,cfg)
% Completed physical access controls when a campaign may schedule data.
% RA schedules are absolute zero-based slots. A campaign's one-based rows
% remain gated THROUGH the completion slot, not merely until its start.
assert(isstruct(result) && isscalar(result) && ...
    all(isfield(result,{'RACompleted','StrictOk','RequireRRCSetupComplete','Msg4ScheduledSlot'})), ...
    'sixgr:truth:MissingRACompletionEvidence','Retain the actual physical RA completion result.');
assert(isequal(result.RACompleted,true) && isequal(result.StrictOk,true), ...
    'sixgr:truth:IncompleteRAAttach','Incomplete or unqualified random access cannot release data.');
completionSlot0=double(result.Msg4ScheduledSlot);
finalStage="Msg4";
localSlot(completionSlot0);
required=result.RequireRRCSetupComplete;
assert(islogical(required) && isscalar(required), ...
    'sixgr:truth:MissingRACompletionEvidence','RequireRRCSetupComplete must be explicit.');
if required
    names={'SetupCompleteScheduledSlot','RRCSetupCompleteCRC', ...
        'RRCSetupCompleteDecoded','RRCConnected'};
    assert(all(isfield(result,names)) && isequal(result.RRCSetupCompleteCRC,true) && ...
        isequal(result.RRCSetupCompleteDecoded,true) && isequal(result.RRCConnected,true), ...
        'sixgr:truth:IncompleteRRCSetupComplete', ...
        'Msg4 alone is not completed RRC when SetupComplete is required.');
    rrcSlot0=double(result.SetupCompleteScheduledSlot);
    localSlot(rrcSlot0);
    assert(rrcSlot0>=completionSlot0,'sixgr:truth:RACompletionClockMismatch', ...
        'Received RRCSetupComplete cannot precede its Msg4/RRCSetup.');
    completionSlot0=rrcSlot0;
    finalStage="RRCSetupComplete";
end
blockedSlotCount=completionSlot0+1;
if nargout>1 || nargin>1
    assert(nargin>1 && isstruct(cfg),'sixgr:truth:MissingRAReceiveCompletion', ...
        'Scheduling release needs the carrier clock and actual receive completion, not just the scheduled slot.');
    rows=sixgr.util.structGet(result,'RuntimeStageRows',table());
    names={'StageName','StageSlot','ObservationStartSample','ObservationEndSampleExclusive', ...
        'ObservationSampleRateHz','ObservationCompletionTime_s','ObservationCoverageSource'};
    assert(istable(rows) && all(ismember(names,rows.Properties.VariableNames)), ...
        'sixgr:truth:MissingRAReceiveCompletion','Retain actual received stage-window evidence.');
    selected=rows(string(rows.StageName)==finalStage & rows.StageSlot==completionSlot0,:);
    assert(height(selected)==1,'sixgr:truth:MissingRAReceiveCompletion', ...
        'Release requires one unambiguous completed final-stage receive window.');
    first=double(selected.ObservationStartSample); last=double(selected.ObservationEndSampleExclusive);
    fs=double(selected.ObservationSampleRateHz);
    samplesPerSlot=fs*sixgr.time.slotDurationSec(cfg);
    assert(isfinite(first) && first>=0 && first==fix(first) && ...
        isfinite(last) && last>first && last==fix(last) && last<flintmax && ...
        isfinite(fs) && fs>0 && isfinite(samplesPerSlot) && samplesPerSlot>0 && ...
        samplesPerSlot==fix(samplesPerSlot) && ...
        selected.ObservationCompletionTime_s==last/fs && ...
        last>completionSlot0*samplesPerSlot && ...
        any(string(selected.ObservationCoverageSource)==[ ...
            "complete_contiguous_received_sample_buffer","executed_runtime_channel_sample_extent"]), ...
        'sixgr:truth:RAReceiveCompletionClockMismatch','Invalid or inconsistent received completion evidence.');
    % A real filter tail can cross a slot boundary. Do not release data at
    % the nominal TX slot end while the final access decoder is still busy.
    blockedSlotCount=max(blockedSlotCount,ceil(last/samplesPerSlot));
end
end

function localSlot(slot)
assert(isnumeric(slot) && isscalar(slot) && isreal(slot) && isfinite(slot) && ...
    slot>=0 && slot==fix(slot) && slot<flintmax, ...
    'sixgr:truth:RACompletionClockMismatch','Completion needs an exact nonnegative absolute slot.');
end
