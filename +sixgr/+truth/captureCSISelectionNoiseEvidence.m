function disturbance=captureCSISelectionNoiseEvidence(planes,receiverOFDMInfo,identity,numRx,receiverWindowID)
%CAPTURECSISELECTIONNOISEEVIDENCE Bind actual nominal noise after CSI receipt.
% Reuse the production noise binder on ORIGINAL completed post-RF observation
% segments. Its pre-RF injected variance is combined with the recorded native
% receiver OFDM transform, never with an estimated post-RF variance. This is
% nominal noise-only scoring evidence, not actual total impaired disturbance.
% No IQ is read, and no noise/channel/RF/calibration execution is performed.
% The caller binds the complete identity (including sample hash/run scope) to
% this same observation; an epoch alone does not identify a recreated stream.
arguments
    planes struct
    receiverOFDMInfo (1,1) struct
    identity (1,1) struct
    numRx (1,1) double {mustBeInteger,mustBePositive}
    receiverWindowID (1,1) string
end
ids=string({planes.ReceiverID}); selected=find(endsWith(ids,':post_rf'));
assert(isscalar(selected),'sixgr:truth:CSISelectionNoiseEndpoint', ...
    'Exactly one original post-RF endpoint must own this completed capture.');
plane=planes(selected); observation=plane.Observation;
localFields(identity,["ObservationID","ReceiverID","ReceiverClockDomain", ...
    "ReceiverClockEpoch","ObservationStartSample","ObservationEndSampleExclusive","SampleRateHz"]);
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && ...
    isscalar(observation) && observation.isComplete(), ...
    'sixgr:truth:CSISelectionNoiseObservation','Use the actual completed observation owner.');
receiver=extractBefore(ids(selected),':post_rf');
assert(localText(identity.ObservationID) && localText(identity.ReceiverID) && ...
    string(identity.ReceiverID)==receiver && ...
    string(identity.ReceiverClockDomain)=="shared_receiver_sample_clock/v1" && ...
    identity.ObservationStartSample==observation.StartSample && ...
    identity.ObservationEndSampleExclusive==observation.EndSampleExclusive && ...
    identity.SampleRateHz==observation.SampleRateHz && ...
    numRx==observation.NumReceiveAntennas, ...
    'sixgr:truth:CSISelectionNoiseIdentity','Receiver, bounds, native sample clock and RX branches must match the actual owner.');
validateattributes(identity.ReceiverClockEpoch,{'numeric'}, ...
    {'scalar','real','finite','integer','nonnegative'});
% Completed planes deliberately omit ID: the shared owner retains the
% observation-window identity once on the parent completion item. Consume
% that actual identity explicitly instead of manufacturing a plane alias.
assert(localText(receiverWindowID) && isfield(identity,'ReceiverWindowID') && ...
    string(identity.ReceiverWindowID)==receiverWindowID, ...
    'sixgr:truth:CSISelectionNoiseObservation','Retain the actual parent observation-window identity.');
if isfield(plane,'ID')
    assert(localText(plane.ID) && string(plane.ID)==receiverWindowID, ...
        'sixgr:truth:CSISelectionNoiseObservation','An optional plane identity must agree with its actual owner.');
end
% Private one-row marker for this actual observation, not a primary result or
% a substitute noise row. The existing binder owns all mode/coverage checks.
record=table(string(identity.ObservationID),'VariableNames',{'ObservationID'});
record=sixgr.truth.bindSharedNoiseReferenceEvidence(record,planes);
assert(ismember('InjectedSampleNoiseVariance',record.Properties.VariableNames), ...
    'sixgr:truth:CSISelectionNoiseMissing','This completed observation has no actual physical noise receipt.');
segments=plane.Segments; compact=repmat(struct('StartSample',0, ...
    'EndSampleExclusive',0,'Source',"",'ApproximationMode',"", ...
    'ConfigurationEpoch',0,'SampleRateHz',0),numel(segments),1);
for k=1:numel(segments)
    segment=segments{k}; e=segment.Execution;
    localFields(e,["Source","ApproximationMode","ConfigurationEpoch","SampleRateHz", ...
        "StartSample","EndSampleExclusive"]);
    assert(string(e.Source)=="composed_tx_retained_rf_per_link_channel_sum_receiver_noise_rf" && ...
        string(e.ApproximationMode)=="none" && ...
        e.ConfigurationEpoch==identity.ReceiverClockEpoch && e.SampleRateHz==identity.SampleRateHz && ...
        segment.StartSample==e.StartSample && segment.EndSampleExclusive==e.EndSampleExclusive, ...
        'sixgr:truth:CSISelectionNoiseExecution','Use matching actual physical segment clocks/epoch, not aliased report configuration.');
    validateattributes([e.StartSample,e.EndSampleExclusive],{'numeric'}, ...
        {'real','finite','integer','nonnegative'});
    compact(k)=struct('StartSample',double(e.StartSample), ...
        'EndSampleExclusive',double(e.EndSampleExclusive),'Source',string(e.Source), ...
        'ApproximationMode',string(e.ApproximationMode), ...
        'ConfigurationEpoch',double(e.ConfigurationEpoch),'SampleRateHz',double(e.SampleRateHz));
end
[native,transform]=localNativeOFDM(receiverOFDMInfo,identity.SampleRateHz);
sampleVariance=double(record.InjectedSampleNoiseVariance);
gain=double(native.SampleToGridNoiseVarianceGain);
gridVariance=sampleVariance*gain;
assert(isfinite(gridVariance) && gridVariance>0, ...
    'sixgr:truth:CSISelectionNoiseTransform','Executed sample variance times native FFT gain must remain finite and positive.');
unit=string(record.NoiseReferenceWaveformAmplitudeUnit);
assert(ismember(unit,["sqrt_mW","normalized_complex_baseband"]), ...
    'sixgr:truth:CSISelectionNoiseUnit','The executed waveform amplitude unit must have an explicit squared-power interpretation.');
varianceUnit="normalized_complex_baseband_squared";
if unit=="sqrt_mW", varianceUnit="mW"; end
receipt=struct('ContractVersion',"sixgr_CSI_selection_noise_receipt/v1", ...
    'ReceiverID',receiver,'ReceiverWindowID',receiverWindowID, ...
    'ReceiverClockDomain',string(identity.ReceiverClockDomain), ...
    'ReceiverClockEpoch',double(identity.ReceiverClockEpoch), ...
    'ReceiverClockEpochSource',"original_physical_execution_ConfigurationEpoch_within_this_observation_not_global_instance_id", ...
    'ObservationStartSample',double(observation.StartSample), ...
    'ObservationEndSampleExclusive',double(observation.EndSampleExclusive), ...
    'SampleRateHz',double(observation.SampleRateHz),'NumRx',numRx, ...
    'Segments',compact,'ValidatedNoiseRecord',table2struct(record), ...
    'NativeOFDM',native,'NoiseTransform',transform, ...
    'ValidationSource',"sixgr.truth.bindSharedNoiseReferenceEvidence_on_original_observation_planes", ...
    'AdditionalNoiseExecutions',0,'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0, ...
    'AdditionalOFDMCalibrationExecutions',0);
disturbance=struct('Source',"executed_pre_rx_rf_noise_with_recorded_ofdm_gain", ...
    'ReferencePlane',"nominal_linear_CSI_RS_port_channel_on_actual_RX_FFT_clock", ...
    'Identity',identity,'SampleNoiseVariance',sampleVariance, ...
    'NoiseStreamSeed',double(record.NoiseStreamSeed),'SampleToGridNoiseVarianceGain',gain, ...
    'Covariance',gridVariance*eye(numRx),'WaveformAmplitudeUnit',unit, ...
    'NoiseVarianceUnit',varianceUnit, ...
    'SampleNoiseVarianceUnit',varianceUnit,'CovarianceUnit',varianceUnit, ...
    'SampleNoiseVarianceReferencePlane',string(record.InjectedSampleNoiseVarianceDomain), ...
    'NoiseVarianceReferencePlane',"native_OFDM_raw_grid_coefficient_squared_amplitude_not_time_average_TX_power", ...
    'NoiseReceipt',receipt, ...
    'NoiseReceiptSHA256',sixgr.util.sha256Hex(jsonencode(receipt)));
end

function [native,c]=localNativeOFDM(info,fs)
fields=["EngineUsed","Nfft","SampleRate","CyclicPrefixFraction", ...
    "FFTWindowPositionSource","SampleToGridNoiseVarianceGain","WaveformSHA256","GridSHA256"];
localFields(info,[fields,"NoiseTransform"]);
c=info.NoiseTransform;
assert(isstruct(c) && isscalar(c),'sixgr:truth:CSISelectionNoiseTransform', ...
    'Retain the actual receiver OFDM transform calibration record.');
localFields(c,["Version","Source","CalibrationKey","Nfft","SampleRate", ...
    "NativeSampleRate","CyclicPrefixFraction","SampleToGridNoiseVarianceGain", ...
    "SampleToGridNoiseVarianceGainSource","SamplePartitionStatus", ...
    "FrequencyDomainSignalPowerReference"]);
validateattributes(info.Nfft,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(info.SampleToGridNoiseVarianceGain,{'numeric'},{'scalar','real','finite','positive'});
validateattributes(info.CyclicPrefixFraction,{'numeric'},{'scalar','real','finite','>=',0,'<=',1});
assert(string(info.EngineUsed)=="canonical_nrOFDMDemodulate" && ...
    string(c.Version)=="ofdm_noise_transform/v2" && ...
    string(c.Source)=="deterministic_impulse_and_white_noise_toolbox_ofdm_calibration" && ...
    localText(c.CalibrationKey) && localText(info.FFTWindowPositionSource) && ...
    localText(info.WaveformSHA256) && localText(info.GridSHA256) && ...
    info.SampleRate==fs && c.SampleRate==fs && c.NativeSampleRate==fs && ...
    info.Nfft==c.Nfft && info.CyclicPrefixFraction==c.CyclicPrefixFraction && ...
    info.SampleToGridNoiseVarianceGain==c.SampleToGridNoiseVarianceGain && ...
    string(c.SamplePartitionStatus)=="exact_native_sample_clock" && ...
    string(c.FrequencyDomainSignalPowerReference)=="occupied_resource_grid_RE" && ...
    ismember(string(c.SampleToGridNoiseVarianceGainSource), ...
        ["fft_length_transform_gain_verified_by_white_noise", ...
        "white_noise_measured_gain_after_fft_length_verification_failed"]), ...
    'sixgr:truth:CSISelectionNoiseTransform', ...
    'The recorded native receiver transform/gain must match this exact FFT/sample-clock contract.');
if string(c.SampleToGridNoiseVarianceGainSource)=="fft_length_transform_gain_verified_by_white_noise"
    assert(info.SampleToGridNoiseVarianceGain==info.Nfft, ...
        'sixgr:truth:CSISelectionNoiseTransform','A declared FFT-length gain must equal the retained Nfft.');
end
native=struct();
for name=fields, native.(name)=info.(name); end
end

function localFields(value,names)
assert(isstruct(value) && isscalar(value) && all(isfield(value,names)), ...
    'sixgr:truth:CSISelectionNoiseMetadata','Required actual noise/receiver metadata is missing.');
end

function valid=localText(value)
value=string(value);
valid=isscalar(value) && ~ismissing(value) && strlength(strtrim(value))>0;
end
