function binding=puschUCIObservationBinding(grant,observation)
% Bind a scheduled UL DCI identity to exact completed receive-window metadata.
% A window hash is not PHY proof. The shared owner must separately establish
% the scheduled HARQ/CSI obligation and deliver the actual observation object.
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && isscalar(observation), ...
    'sixgr:truth:MissingPUSCHUCIObservation','Retain the actual completed PUSCH receive buffer.');
assert(observation.isComplete(),'WAVEFORM:IncompleteObservation','PUSCH UCI requires complete received samples.');
sixgr.phy.grant.assertGrantTimingIdentity(grant,'UL');
assert(isfield(grant,'PHYGrant') && isfield(grant,'DCI') && ...
    isfield(grant.DCI,'ContextData') && isfield(grant.DCI,'Bits'), ...
    'sixgr:truth:MissingPUSCHUCIScheduledAssignment','Retain the scheduled UL DCI and frozen PHY grant.');
packed=sixgr.phy.pdcch.decodeDCIPayload(grant.DCI.Bits,'0_1',grant.DCI.ContextData);
context=sixgr.phy.pdcch.DCIContext(grant.DCI.ContextData);
assignment=struct('GrantContextID',string(grant.PHYGrant.GrantContextId), ...
    'ScheduledULPayloadHash',string(packed.PayloadHash));
assert(strlength(assignment.GrantContextID)>0 && ~ismissing(assignment.GrantContextID), ...
    'sixgr:truth:MissingPUSCHUCIScheduledAssignment','Retain the frozen UL grant identity.');
assignmentDigest=sixgr.phy.pucch.PUCCHUtil.hash(assignment);
window=struct('AssignmentDigest',assignmentDigest,'StartSample',observation.StartSample, ...
    'EndSampleExclusive',observation.EndSampleExclusive,'SampleRateHz',observation.SampleRateHz, ...
    'NumReceiveAntennas',observation.NumReceiveAntennas);
binding=struct('ObservationID',"PUSCH-UCI-"+sixgr.phy.pucch.PUCCHUtil.hash(window), ...
    'AssignmentDigest',assignmentDigest,'ConfigurationEpoch',double(context.Data.ConfigurationEpoch));
end
