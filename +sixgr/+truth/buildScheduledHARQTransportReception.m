function hypothesis=buildScheduledHARQTransportReception(state,cfg,ue,targetSlot,observationID)
% Independent HARQ-only gNB allocation from actual transmitted DL grants.
% Select the gNB's scheduled HARQ transport independently of UE reception.
% Combined CSI/SR remain guarded; do not borrow UE serialized payload length.
assert(~logical(sixgr.util.structGet(cfg,'phy.csi.reportCSI',true)), ...
    'sixgr:truth:UnresolvedCombinedPUCCHReceiveHypothesis', ...
    'HARQ-only receive ownership requires CSI reporting disabled; combined CSI hypotheses remain separate.');
uciOnPUSCH=sixgr.util.structGet(cfg,'phy.pucch.uciOnPUSCHEnabled',[]);
assert((islogical(uciOnPUSCH)||isnumeric(uciOnPUSCH)) && isscalar(uciOnPUSCH) && ...
    isreal(uciOnPUSCH) && isfinite(uciOnPUSCH) && any(uciOnPUSCH==[0 1]), ...
    'sixgr:truth:InvalidPUCCHTransportConfiguration','UCI-on-PUSCH enablement must be explicitly binary.');
mapping=sixgr.truth.buildScheduledHARQACKMapping(state,cfg,ue,targetSlot);
grant=mapping.LastGrant;
cellId=double(grant.ServingCell);
identity=cfg.phy.frame.DefaultIdentity;
ueData=struct('UEID',ue,'RNTI',mapping.RNTI,'ServingCell',cellId,'PUCCHCell',cellId, ...
    'ComponentCarrier',identity.ScheduledCCID,'ActiveULBWP',identity.ULBWPID);
rrc=sixgr.phy.pucch.PUCCHConfigBuilder.receiverConfiguration(cfg,ueData);
srCalendar=table();
if ~isempty(rrc.Data.SRResources) || ~isempty(sixgr.util.structGet( ...
        cfg,'validation.pucch_resources.scheduling_request_resources',struct([])))
    srCalendar=sixgr.truth.buildConfiguredSRCalendar(cfg,ueData,targetSlot,targetSlot);
end
context=sixgr.truth.buildConfiguredPUCCHReceiveContext(struct( ...
    'ObservationID',string(observationID),'ConfigurationEpoch',mapping.ConfigurationEpoch, ...
    'HARQBitCount',mapping.BitCount,'SRBitCount',0,'PriorityIndex',0, ...
    'CSIReportConfigID',"",'CSIConfigurationEpoch',NaN));
set=sixgr.phy.pucch.PUCCHResourceSetResolver.resolveBitCount(mapping.BitCount,rrc,mapping.ConfigurationEpoch);
packed=sixgr.phy.pdcch.decodeDCIPayload(grant.DCI.Bits,grant.DCI.Format,grant.DCI.ContextData);
priRow=struct('ResourceSetID',set.ID,'ResourceListSize',numel(set.ResourceIDs), ...
    'PRIFieldWidth',3,'PRIValue',double(packed.Fields.pucch_resource_indicator), ...
    'FirstCCE',sixgr.util.structGet(grant,'PDCCHGrantFirstCCE',NaN), ...
    'NumCCE',sixgr.util.structGet(grant,'PDCCHGrantNumCCE',NaN), ...
    'RequiresSet0CCEFormula',set.ID==0 && numel(set.ResourceIDs)>8);
pri=sixgr.phy.pucch.PUCCHResourceIndicatorResolver.resolveVector(priRow);
assert(pri.Valid,'sixgr:truth:InvalidScheduledPUCCHResource','The transmitted DCI must select a valid configured PUCCH resource.');
resource=rrc.resourceByID(set.ResourceIDs(pri.Ordinal));
transport=struct(); overlapping=cell(0,1);
if uciOnPUSCH
    [overlapping,transport]=sixgr.truth.findScheduledPUSCHOverlap(state,cfg,ue,targetSlot, ...
        [resource.Data.StartSymbol resource.Data.NumSymbols]);
end
% Resource inventory alone does not mean an SR occurs in this slot. Use
% installed receiver-side occasions, never a UE pending-positive flag.
% General SR/HARQ multiplexing and priority arbitration are not implemented
% by this HARQ-only hypothesis: all actual time overlaps still fail closed.
if ~isempty(srCalendar)
    overlap=srCalendar.ULResourceAvailable & ...
        srCalendar.StartSymbol<resource.Data.StartSymbol+resource.Data.NumSymbols & ...
        resource.Data.StartSymbol<srCalendar.StartSymbol+srCalendar.NumSymbols;
    assert(~any(overlap),'sixgr:truth:UnresolvedSRPUCCHReceiveHypothesis', ...
        'An installed SR opportunity overlaps this HARQ resource; a combined SR receive hypothesis is required.');
end
% Scheduling resource legality is checked on the configured feedback slot.
[~,~,~,partition]=sixgr.truth.CoupledTruthRuntime.resolveSlotPartition(cfg,targetSlot);
symbols=resource.Data.StartSymbol+(0:resource.Data.NumSymbols-1);
ul=partition.ULSymbolAllocation;
assert(all(symbols>=ul(1) & symbols<sum(ul)), ...
    'sixgr:truth:ScheduledPUCCHOutsideUL','The gNB receive resource must occupy resolved UL symbols.');
assignment=sixgr.phy.pucch.PUCCHReceptionAssignment(struct( ...
    'ObservationID',string(observationID),'ResourceID',resource.ID,'RNTI',mapping.RNTI, ...
    'AbsoluteSlot0',targetSlot-1,'Source',mapping.Source, ...
    'TimingSource','received_UL_pilot_not_UE_transmit_origin'),rrc,context);
hypothesis=struct('SelectedTransport',"PUCCH",'Mapping',mapping,'Assignment',assignment,'Context',context, ...
    'TransportScheduleEvidence',transport, ...
    'Source',"gnb_actual_transmitted_schedule_and_installed_RRC");
if ~isempty(overlapping)
    assert(isscalar(overlapping),'sixgr:truth:AmbiguousScheduledUCITransport', ...
        'Multiple overlapping scheduled PUSCHs require explicit receiver selection.');
    command=overlapping{1};
    [csi,report]=sixgr.truth.buildSharedPUSCHCSIReceiveObligation(cfg,command.Binding.Grant);
    [puschContext,puschMapping]=sixgr.truth.buildSharedPUSCHUCIReceiveContext( ...
        state,cfg,command.Binding.Grant,string(observationID),csi,report);
    assert(isempty(report) && ~isempty(puschMapping), ...
        'sixgr:truth:UnresolvedCombinedPUCCHReceiveHypothesis','This selector owns HARQ-only scheduled transport.');
    hypothesis.SelectedTransport="PUSCH";
    hypothesis.ScheduledULControl=command;
    hypothesis.PUSCHMapping=puschMapping;
    % This is a selection-time schema, not the eventual PUSCH capture's
    % observation identity. Completion rebuilds against its actual window.
    hypothesis.PUSCHSelectionContext=puschContext;
end
end
