function hypothesis=buildScheduledHARQTransportReception(state,cfg,ue,targetSlot,observationID)
% Independent gNB allocation from transmitted DL grants and installed UCI.
% Select the gNB's scheduled HARQ transport independently of UE reception.
% Never borrow UE report presence, serialized payload length or selected RI.
uciOnPUSCH=sixgr.util.structGet(cfg,'phy.pucch.uciOnPUSCHEnabled',[]);
assert((islogical(uciOnPUSCH)||isnumeric(uciOnPUSCH)) && isscalar(uciOnPUSCH) && ...
    isreal(uciOnPUSCH) && isfinite(uciOnPUSCH) && any(uciOnPUSCH==[0 1]), ...
    'sixgr:truth:InvalidPUCCHTransportConfiguration','UCI-on-PUSCH enablement must be explicitly binary.');
mapping=sixgr.truth.buildScheduledHARQACKMapping(state,cfg,ue,targetSlot);
grant=mapping.LastGrant;
cellId=double(grant.ServingCell);
identity=cfg.phy.frame.DefaultIdentity;
ueData=struct('UEID',ue,'RNTI',mapping.RNTI,'ServingCell',cellId,'PUCCHCell',cellId, ...
    'ComponentCarrier',identity.ScheduledCCID,'ActiveULBWP',identity.ULBWPID);
rrc=sixgr.phy.pucch.PUCCHConfigBuilder.receiverConfiguration(cfg,ueData);
csiCalendar=sixgr.truth.configuredCSIReportCalendar(cfg,ueData,targetSlot);
srCalendar=table();
if ~isempty(rrc.Data.SRResources) || ~isempty(sixgr.util.structGet( ...
        cfg,'validation.pucch_resources.scheduling_request_resources',struct([])))
    srCalendar=sixgr.truth.buildConfiguredSRCalendar(cfg,ueData,targetSlot,targetSlot);
end
packed=sixgr.phy.pdcch.decodeDCIPayload(grant.DCI.Bits,grant.DCI.Format,grant.DCI.ContextData);
resource=localResource(mapping.BitCount,rrc,mapping,packed);
csiOverlap=false(height(csiCalendar),1);
if ~isempty(csiCalendar)
    csiOverlap=csiCalendar.ULResourceAvailable & ...
        csiCalendar.StartSymbol<resource.Data.StartSymbol+resource.Data.NumSymbols & ...
        resource.Data.StartSymbol<csiCalendar.StartSymbol+csiCalendar.NumSymbols;
end
windows=[resource.Data.StartSymbol resource.Data.NumSymbols];
report=[]; reportID=""; reportEpoch=NaN;
if any(csiOverlap)
    assert(nnz(csiOverlap)==1,'sixgr:truth:UnresolvedCombinedPUCCHReceiveHypothesis', ...
        'Multiple installed CSI reports need an explicit ordered receive procedure.');
    selected=csiCalendar(csiOverlap,:);
    assert(isfinite(selected.CSIReferenceSlot) && selected.CSIReferenceSlot>= ...
        sixgr.util.structGet(state,'SweepPointStartSlot',1), ...
        'sixgr:truth:MissingConfiguredCSIReceiveOccasion','Retain a causal installed CSI reference resource.');
    report=sixgr.phy.mimo.CSIReportConfiguration( ...
        cfg.phy.csi.reportConfiguration,cfg.phy.csi.reportConfigurationEpoch);
    reportID=report.ReportConfigID; reportEpoch=report.Epoch;
    windows=[windows;selected.StartSymbol selected.NumSymbols];
end
% SR count comes from the union of the pre-multiplexing HARQ and CSI
% resources, not from UE positive/negative SR state or the final allocation.
srBits=0; srOverlap=struct();
if ~isempty(srCalendar)
    srOverlap=sixgr.truth.resolveConfiguredSROverlap(srCalendar,targetSlot,windows,0);
    srBits=srOverlap.EncodedBitCount;
end
assert(~(isempty(report) && mapping.BitCount<=2 && srBits>0), ...
    'sixgr:truth:UnresolvedSRPUCCHReceiveHypothesis', ...
    'Short HARQ/SR resource hypotheses require separate receiver qualification.');
context=sixgr.truth.buildConfiguredPUCCHReceiveContext(struct( ...
    'ObservationID',string(observationID),'ConfigurationEpoch',mapping.ConfigurationEpoch, ...
    'HARQBitCount',mapping.BitCount,'SRBitCount',srBits,'PriorityIndex',0, ...
    'CSIReportConfigID',reportID,'CSIConfigurationEpoch',reportEpoch),report);
resource=localResource(context.Sequence1Length+context.Sequence2Length,rrc,mapping,packed);
transport=struct(); overlapping=cell(0,1);
if uciOnPUSCH
    [overlapping,transport]=sixgr.truth.findScheduledPUSCHOverlap(state,cfg,ue,targetSlot, ...
        [resource.Data.StartSymbol resource.Data.NumSymbols]);
end
% Scheduling resource legality is checked on the configured feedback slot.
[~,~,~,partition]=sixgr.truth.CoupledTruthRuntime.resolveSlotPartition(cfg,targetSlot);
symbols=resource.Data.StartSymbol+(0:resource.Data.NumSymbols-1);
ul=partition.ULSymbolAllocation;
assert(all(symbols>=ul(1) & symbols<sum(ul)), ...
    'sixgr:truth:ScheduledPUCCHOutsideUL','The gNB receive resource must occupy resolved UL symbols.');
procedure="dynamic_harq";
if ~isempty(report), procedure="dynamic_harq_csi"; end
assignment=sixgr.phy.pucch.PUCCHReceptionAssignment(struct( ...
    'ObservationID',string(observationID),'ResourceID',resource.ID,'RNTI',mapping.RNTI, ...
    'AbsoluteSlot0',targetSlot-1,'Source',mapping.Source, ...
    'TimingSource','received_UL_pilot_not_UE_transmit_origin', ...
    'ResourceSelectionProcedure',procedure),rrc,context);
hypothesis=struct('SelectedTransport',"PUCCH",'Mapping',mapping,'Assignment',assignment,'Context',context, ...
    'UEIndex',ue,'RNTI',mapping.RNTI,'TargetSlot',targetSlot,'ServingCell',cellId, ...
    'CSIReportCalendar',csiCalendar,'CSIReportResourceOverlap',csiOverlap, ...
    'CSIReportConfiguration',report,'SROverlap',srOverlap, ...
    'TransportScheduleEvidence',transport, ...
    'Source',"gnb_actual_transmitted_schedule_and_installed_RRC");
if ~isempty(overlapping)
    assert(isscalar(overlapping),'sixgr:truth:AmbiguousScheduledUCITransport', ...
        'Multiple overlapping scheduled PUSCHs require explicit receiver selection.');
    command=overlapping{1};
    [csi,puschReport,puschCalendar]=sixgr.truth.buildSharedPUSCHCSIReceiveObligation(cfg,command.Binding.Grant);
    if ~isempty(report)
        assert(~isempty(puschReport) && height(puschCalendar)==1 && ...
            puschCalendar.ObligationID==selected.ObligationID && ...
            puschReport.ReportConfigID==report.ReportConfigID && puschReport.Epoch==report.Epoch, ...
            'sixgr:truth:CSITransportObligationMismatch', ...
            'The scheduled PUSCH must retain the same overlapping installed CSI obligation.');
    end
    [puschContext,puschMapping]=sixgr.truth.buildSharedPUSCHUCIReceiveContext( ...
        state,cfg,command.Binding.Grant,string(observationID),csi,puschReport);
    assert(~isempty(puschMapping), ...
        'sixgr:truth:UnresolvedCombinedPUCCHReceiveHypothesis','Scheduled PUSCH must retain its HARQ obligation.');
    hypothesis.SelectedTransport="PUSCH";
    hypothesis.ScheduledULControl=command;
    hypothesis.PUSCHMapping=puschMapping;
    % This is a selection-time schema, not the eventual PUSCH capture's
    % observation identity. Completion rebuilds against its actual window.
    hypothesis.PUSCHSelectionContext=puschContext;
end
end

function resource=localResource(count,rrc,mapping,packed)
set=sixgr.phy.pucch.PUCCHResourceSetResolver.resolveBitCount(count,rrc,mapping.ConfigurationEpoch);
grant=mapping.LastGrant;
row=struct('ResourceSetID',set.ID,'ResourceListSize',numel(set.ResourceIDs), ...
    'PRIFieldWidth',3,'PRIValue',double(packed.Fields.pucch_resource_indicator), ...
    'FirstCCE',sixgr.util.structGet(grant,'PDCCHGrantFirstCCE',NaN), ...
    'NumCCE',sixgr.util.structGet(grant,'PDCCHGrantNumCCE',NaN), ...
    'RequiresSet0CCEFormula',set.ID==0 && numel(set.ResourceIDs)>8);
pri=sixgr.phy.pucch.PUCCHResourceIndicatorResolver.resolveVector(row);
assert(pri.Valid,'sixgr:truth:InvalidScheduledPUCCHResource', ...
    'The transmitted DCI must select a valid configured PUCCH resource.');
resource=rrc.resourceByID(set.ResourceIDs(pri.Ordinal));
end
