function T=bindSharedTransmitOccupancy(T,state,item)
% Bind compact TX audit AFTER independent receiver execution has completed.
% Neither this audit nor the paired-overlap collector authorizes a receiver.
assert(istable(T) && height(T)==1 && any(string(item.Kind)==["PUSCH","PUCCH"]), ...
    'sixgr:truth:TransmitOccupancyCompletion','Bind one actual UL receiver trial.');
owner=state.SharedWaveformStream; prepared=item.Context.Prepared;
if string(item.Kind)=="PUSCH"
    identity=sixgr.truth.preparedDataTransmissionIdentity(prepared,item.UE);
    records=owner.DataTransmissions;
    ledger=sixgr.util.structGet(state,'SharedDataTXLedger',{});
else
    identity=sixgr.truth.preparedPUCCHTransmissionIdentity(prepared,item.UE,item.ID);
    records=owner.PUCCHTransmissions;
    ledger=sixgr.util.structGet(state,'SharedPUCCHTXLedger',{});
end
hit=find(arrayfun(@(x)x.Identity.TransmissionID==identity.TransmissionID,records));
committed=find(cellfun(@(x)x.Identity.TransmissionID==identity.TransmissionID,ledger));
assert(isscalar(hit) && isscalar(committed) && isequaln(records(hit).Identity,identity) && ...
    isequaln(ledger{committed}.Identity,identity) && ...
    isfield(records,'TransmitOccupancy') && isfield(ledger{committed},'TransmitOccupancy') && ...
    isequaln(records(hit).TransmitOccupancy,ledger{committed}.TransmitOccupancy), ...
    'sixgr:truth:TransmitOccupancyReceipt','Retain the exact physical owner and MAC TX receipt.');
evidence=records(hit).TransmitOccupancy;
planes=string({item.Planes.ReceiverID});
itx=find(planes==string(evidence.Identity.TransmitterID)+":tx");
irx=find(planes=="gnb_"+evidence.Identity.ServingCell+"_rx:post_rf");
assert(isscalar(itx) && isscalar(irx),'sixgr:truth:TransmitOccupancyEndpoint', ...
    'Require the actual same-UE TX and serving-cell RX captures.');
tx=item.Planes(itx).Observation;
rx=item.Planes(irx).Observation;
assert(tx.isComplete() && tx.StartSample==prepared.StartSample && ...
    tx.EndSampleExclusive==prepared.EndSampleExclusive && ...
    tx.SampleRateHz==prepared.SampleRateHz && ...
    evidence.StartSample==tx.StartSample && evidence.EndSampleExclusive==tx.EndSampleExclusive && ...
    evidence.SampleRateHz==tx.SampleRateHz && evidence.Identity.ObservationID==string(item.ID) && ...
    evidence.Identity.ClockEpoch==owner.Physical.ConfigurationEpoch && ...
    records(hit).FirstActiveSample==evidence.ActiveIntervals(1,1) && ...
    records(hit).CommittedAtSample==records(hit).FirstActiveSample+1 && ...
    owner.Events.NextSampleIndex>=evidence.EndSampleExclusive && ...
    rx.isComplete() && rx.SampleRateHz==evidence.SampleRateHz && ...
    owner.Events.NextSampleIndex>=rx.EndSampleExclusive, ...
    'sixgr:truth:TransmitOccupancyCompletion','First-sample receipt alone cannot attest complete emission.');
evidence.EmissionStatus="completed_nonzero_contribution";
evidence.CommittedAtSample=records(hit).CommittedAtSample;
evidence.CompletedAtSample=owner.Events.NextSampleIndex;
evidence.PopulationIdentity=ledger{committed}.TransmitPopulationIdentity;
assert(evidence.PopulationIdentity.BoundAtSample==evidence.CommittedAtSample, ...
    'sixgr:truth:TransmitOccupancyPopulationClock','Source point belongs to the actual TX commit event.');
for name=["UEIndex","RNTI"]
    assert(ismember(name,string(T.Properties.VariableNames)) && ...
        isequal(double(T.(name)),double(evidence.Identity.(name))), ...
        'sixgr:truth:TransmitOccupancyRowIdentity','Receiver trial must belong to the same UE and RNTI.');
end
for name=["ServingCell","BaseStationID"]
    if ismember(name,string(T.Properties.VariableNames)) && isfinite(double(T.(name)))
        assert(double(T.(name))==evidence.Identity.ServingCell, ...
            'sixgr:truth:TransmitOccupancyRowIdentity','Receiver trial serving cell changed.');
    end
end
if string(item.Kind)=="PUCCH"
    sourceField="PhysicalPUCCHOccasionId";
    [sourceIdentity,queueKey,occasionSource]=sixgr.truth.sharedPUCCHReceiverOccasionIdentity(item);
else
    sourceField="FrozenGrantContextId";
    sourceIdentity=string(identity.PHYGrantContextId);
end
assert(ismember(sourceField,string(T.Properties.VariableNames)) && ...
    isscalar(sourceIdentity) && strlength(sourceIdentity)>0 && ...
    string(T.(sourceField))==sourceIdentity, ...
    'sixgr:truth:TransmitOccupancyRowIdentity','Bind the independent receiver row to its actual grant/occasion.');
evidence.ReceiverBinding=struct('ObservationID',string(item.ID), ...
    'ReceiverID',planes(irx),'StartSample',rx.StartSample, ...
    'EndSampleExclusive',rx.EndSampleExclusive,'SampleRateHz',rx.SampleRateHz, ...
    'CompletedAtSample',owner.Events.NextSampleIndex, ...
    'SourceRowIdentityField',sourceField,'SourceRowIdentity',sourceIdentity);
if string(item.Kind)=="PUCCH"
    evidence.ReceiverBinding.QueueKey=queueKey;
    evidence.ReceiverBinding.PhysicalOccasionID=sourceIdentity;
    evidence.ReceiverBinding.OccasionIdentitySource=occasionSource;
end
% These explicit columns are cross-checked against the receipt by the
% collector. Existing receiver bounds remain independent; do not rewrite
% them to make a transplanted receipt appear to match.
rowBinding=struct('TransmitOccupancyObservationID',string(item.ID), ...
    'TransmitOccupancyTransmissionID',string(identity.TransmissionID), ...
    'TransmitOccupancyTXEndpoint',planes(itx),'TransmitOccupancyRXEndpoint',planes(irx), ...
    'TransmitOccupancyClockDomain',string(evidence.Identity.ClockDomain), ...
    'TransmitOccupancyClockEpoch',evidence.Identity.ClockEpoch, ...
    'TransmitOccupancyStartSample',tx.StartSample, ...
    'TransmitOccupancyEndSampleExclusive',tx.EndSampleExclusive, ...
    'TransmitOccupancySampleRateHz',tx.SampleRateHz, ...
    'TransmitOccupancyRXStartSample',rx.StartSample, ...
    'TransmitOccupancyRXEndSampleExclusive',rx.EndSampleExclusive, ...
    'TransmitOccupancyRXSampleRateHz',rx.SampleRateHz, ...
    'TransmitOccupancyCompletedAtSample',owner.Events.NextSampleIndex);
for field=string(fieldnames(rowBinding)).'
    if ismember(field,string(T.Properties.VariableNames))
        old=T.(field); expected=rowBinding.(field);
        if isstring(expected)
            old=string(old);
            matches=isscalar(old) && (ismissing(old) || strlength(old)==0 || old==expected);
        else
            matches=isnumeric(old) && isscalar(old) && (isnan(old) || old==expected);
        end
        % Compatible tables add blank/NaN columns for later unbound rows.
        % Those are missing metadata, not another observation's receipt.
        assert(matches, ...
            'sixgr:truth:TransmitOccupancyRowIdentity','Do not overwrite another receiver binding.');
    end
    T.(field)=rowBinding.(field);
end
T.TransmitOccupancyEvidenceJSON=string(jsonencode(evidence));
T.TransmitOccupancyEvidenceSHA256=string(sixgr.util.sha256Hex(T.TransmitOccupancyEvidenceJSON));
T.TransmitOccupancyStatus=evidence.EmissionStatus;
end
