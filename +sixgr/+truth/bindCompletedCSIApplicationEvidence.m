function trial=bindCompletedCSIApplicationEvidence(trial,evidence)
%BINDCOMPLETEDCSIAPPLICATIONEVIDENCE Lossless post-commit publication only.
% Caller must obtain evidence from buildCompletedCSIApplicationEvidence at
% the real completion boundary. This projection cannot establish execution
% from a user-authored JSON token. Never replace frozen CSIReportApplication
% (which remains not-waveform-qualified) or manufacture missing row identity.
assert(nargin==2 && istable(trial) && height(trial)==1 && ...
    isstruct(evidence) && isscalar(evidence), ...
    'sixgr:truth:CompletedCSIProjectionInput','Project one completed receiver row and original evidence.');
required={'Version','Source','EvidenceJSON','EvidenceSHA256','AdmittedCSI', ...
    'AdmittedCSIJSON','AdmittedCSISHA256','FrozenApplication','TransmissionIdentity','LogicalGrantContextID', ...
    'ReceiverWindowID','ReceiverInput','ReceiverClockDomain','ReceiverClockEpoch', ...
    'ReceiverID','TransmitterID','ReceivedControl','CompletedAtSample','ReceiverOutcome', ...
    'WaveformApplicationVerified','PopulationScopeComplete','PreparedSourcePointScope', ...
    'PreparedSourcePopulation','PreparedSourcePopulationJSON','PreparedSourcePopulationSHA256', ...
    'FullScenarioQualified','AdditionalPHYExecutions'};
assert(all(isfield(evidence,required)) && ...
    string(evidence.Version)=="completed_received_csi_application/v1" && ...
    string(evidence.Source)=="received_CSI_owner_control_record_and_completed_shared_PDSCH" && ...
    isequal(evidence.WaveformApplicationVerified,true) && ...
    isequal(evidence.FrozenApplication.WaveformApplicationVerified,false) && ...
    isequal(evidence.FullScenarioQualified,false) && evidence.AdditionalPHYExecutions==0, ...
    'sixgr:truth:CompletedCSIProjectionEvidence','Require the exact completed-evidence contract, not frozen/started claims.');
payload=rmfield(evidence,{'EvidenceJSON','EvidenceSHA256'});
assert(string(evidence.EvidenceJSON)==string(jsonencode(sixgr.util.jsonSafeValue(payload))) && ...
    string(evidence.EvidenceSHA256)==localSHA(evidence.EvidenceJSON) && ...
    string(evidence.AdmittedCSIJSON)==string(jsonencode(evidence.AdmittedCSI)) && ...
    string(evidence.AdmittedCSISHA256)==localSHA(evidence.AdmittedCSIJSON), ...
    'sixgr:truth:CompletedCSIProjectionHash','Tokens and digests must match the exact original evidence values.');
if strlength(string(evidence.PreparedSourcePopulationJSON))>0
    assert(string(evidence.PreparedSourcePopulationJSON)== ...
        string(jsonencode(sixgr.util.jsonSafeValue(evidence.PreparedSourcePopulation))) && ...
        string(evidence.PreparedSourcePopulationSHA256)==localSHA(evidence.PreparedSourcePopulationJSON), ...
        'sixgr:truth:CompletedCSIProjectionHash','The original preparation-population token must survive unchanged.');
else
    assert(strlength(string(evidence.PreparedSourcePopulationSHA256))==0 && ...
        isstruct(evidence.PreparedSourcePopulation) && isempty(fieldnames(evidence.PreparedSourcePopulation)) && ...
        ~evidence.PopulationScopeComplete, ...
        'sixgr:truth:CompletedCSIProjectionHash','Missing historical source population cannot acquire a digest or complete scope.');
end
names=string(trial.Properties.VariableNames);
required=["Direction","FrozenGrantContextId","ReceivedAssignmentDigest","ReceiverObservationSHA256", ...
    "ObservationStartSample","ObservationEndSampleExclusive","ObservationSampleRateHz", ...
    "CRCPass","CRCApplicable","DLSCHDecodeAttempted","DecodeAttempted","Crash"];
assert(all(ismember(required,names)) && ...
    string(trial.Direction)=="DL" && ...
    string(trial.FrozenGrantContextId)==string(evidence.TransmissionIdentity.PHYGrantContextId) && ...
    string(trial.ReceivedAssignmentDigest)==string(evidence.ReceivedControl.AssignmentDigest) && ...
    string(trial.ReceiverObservationSHA256)==string(evidence.ReceiverInput.ReceiverObservationSHA256) && ...
    isequaln(trial.ObservationStartSample,evidence.ReceiverInput.ObservationStartSample) && ...
    isequaln(trial.ObservationEndSampleExclusive,evidence.ReceiverInput.ObservationEndSampleExclusive) && ...
    isequaln(trial.ObservationSampleRateHz,evidence.ReceiverInput.ObservationSampleRateHz) && ...
    isequal(double(trial.Crash),0) && isequal(double(trial.CRCApplicable),1) && ...
    isequal(double(trial.DLSCHDecodeAttempted),1) && isequal(double(trial.DecodeAttempted),1) && ...
    isequal(double(trial.CRCPass),double(evidence.ReceiverOutcome.CRCPass)), ...
    'sixgr:truth:CompletedCSIProjectionRow','Completion evidence must match this actual receiver row exactly.');
% The sample hash alone does not identify its measurement plane, coverage
% or completion clock. Preserve EVERY field recorded by the original
% receivedWaveformEvidence producer, not only the hash/bounds/Fs subset.
% Missing fields cannot acquire authority from this post-commit projection.
receiverFields=string(fieldnames(evidence.ReceiverInput)).';
assert(all(ismember(receiverFields,names)), ...
    'sixgr:truth:CompletedCSIProjectionRow','Original receiver-input fields must remain present.');
for field=receiverFields
    assert(isequaln(trial.(field),evidence.ReceiverInput.(field)), ...
        'sixgr:truth:CompletedCSIProjectionRow', ...
        'Receiver-input field %s differs from the original completed capture.',field);
end
for field=["UEIndex","RNTI","ServingCell"]
    if ismember(field,names)
        assert(isequal(double(trial.(field)),evidence.AdmittedCSI.(field)), ...
            'sixgr:truth:CompletedCSIProjectionRow','Do not attach another UE/cell receipt.');
    end
end
if ismember("GrantContextId",names) && strlength(string(trial.GrantContextId))>0
    assert(string(trial.GrantContextId)==string(evidence.LogicalGrantContextID), ...
        'sixgr:truth:CompletedCSIProjectionRow','Existing logical grant identity must agree in its own domain.');
end
fields=struct('CompletedCSIApplicationVersion',string(evidence.Version), ...
    'CompletedCSIApplicationSource',string(evidence.Source), ...
    'CompletedCSIApplicationVerified',true, ...
    'CompletedCSIApplicationCompletedAtSample',evidence.CompletedAtSample, ...
    'CompletedCSIApplicationTransmissionID',string(evidence.TransmissionIdentity.TransmissionID), ...
    'CompletedCSIApplicationGrantContextID',string(evidence.TransmissionIdentity.PHYGrantContextId), ...
    'CompletedCSIApplicationLogicalGrantContextID',string(evidence.LogicalGrantContextID), ...
    'CompletedCSIApplicationReceiverWindowID',string(evidence.ReceiverWindowID), ...
    'CompletedCSIApplicationReceiverID',string(evidence.ReceiverID), ...
    'CompletedCSIApplicationTransmitterID',string(evidence.TransmitterID), ...
    'CompletedCSIApplicationReceiverClockDomain',string(evidence.ReceiverClockDomain), ...
    'CompletedCSIApplicationReceiverClockEpoch',evidence.ReceiverClockEpoch, ...
    'CompletedCSIApplicationReportIdentity',string(evidence.AdmittedCSI.ReportIdentity), ...
    'CompletedCSIApplicationReportObservationID',string(evidence.AdmittedCSI.ObservationID), ...
    'CompletedCSIApplicationReceiverObservationSHA256',string(evidence.ReceiverInput.ReceiverObservationSHA256), ...
    'CompletedCSIApplicationAdmittedCSIJSON',string(evidence.AdmittedCSIJSON), ...
    'CompletedCSIApplicationAdmittedCSISHA256',string(evidence.AdmittedCSISHA256), ...
    'CompletedCSIApplicationEvidenceJSON',string(evidence.EvidenceJSON), ...
    'CompletedCSIApplicationEvidenceSHA256',string(evidence.EvidenceSHA256), ...
    'CompletedCSIApplicationPreparedPopulationJSON',string(evidence.PreparedSourcePopulationJSON), ...
    'CompletedCSIApplicationPreparedPopulationSHA256',string(evidence.PreparedSourcePopulationSHA256), ...
    'CompletedCSIApplicationPopulationScopeComplete',evidence.PopulationScopeComplete, ...
    'CompletedCSIApplicationPreparedSourcePointScope',string(evidence.PreparedSourcePointScope));
for name=string(fieldnames(fields)).'
    if ismember(name,names)
        assert(isequaln(trial.(name),fields.(name)), ...
            'sixgr:truth:CompletedCSIProjectionConflict','Never overwrite an existing %s value.',name);
    else
        trial.(name)=fields.(name);
    end
end
end

function sha=localSHA(token)
sha=string(sixgr.util.sha256Hex(uint8(unicode2native(char(token),'UTF-8'))));
end
