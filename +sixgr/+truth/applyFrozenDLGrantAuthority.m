function cfgOut = applyFrozenDLGrantAuthority(cfgIn, grant, stage)
%APPLYFROZENDLGRANTAUTHORITY Restore and verify an immutable DL PHYGrant.
% Keep this file ASCII-only.

if nargin < 3
    stage = "execution_grant_hydration";
end
phyGrant = sixgr.util.structGet(grant, "PHYGrant", struct());
if ~(isstruct(phyGrant) && ~isempty(fieldnames(phyGrant)) && ...
        logical(sixgr.util.structGet(phyGrant, "IsFrozen", false)))
    error("sixgr:truth:MissingFrozenDLPHYGrant", ...
        "DL grant authority at stage '%s' requires an immutable PHYGrant.", ...
        char(string(stage)));
end
if upper(string(sixgr.util.structGet(phyGrant, "Direction", ""))) ~= "DL"
    error("sixgr:truth:FrozenDLPHYGrantDirectionMismatch", ...
        "Frozen grant authority at stage '%s' received direction '%s'.", ...
        char(string(stage)), char(string(sixgr.util.structGet(phyGrant, "Direction", ""))));
end

cfgOut = sixgr.phy.grant.applyPHYGrantToConfig(cfgIn, phyGrant);
prec = sixgr.util.structGet(phyGrant, "PrecodingState", struct());
expectedLogical = double(sixgr.util.structGet(prec, "MatrixLogicalPorts", []));
if isempty(expectedLogical)
    error("sixgr:truth:FrozenDLLogicalPrecoderMissing", ...
        "Frozen DL PHYGrant at stage '%s' does not contain MatrixLogicalPorts.", ...
        char(string(stage)));
end
expectedLogicalDigest = string(sixgr.phy.mimo.MatrixContract.digest(expectedLogical));
paths = ["phy.pdsch.precoding.matrix", "phy.pdsch.precodingMatrix", "phy.pdsch.W"];
for pathIdx = 1:numel(paths)
    actual = sixgr.util.structGet(cfgOut, paths(pathIdx), []);
    actualDigest = "";
    if isnumeric(actual) && ~isempty(actual)
        actualDigest = string(sixgr.phy.mimo.MatrixContract.digest(double(actual)));
    end
    if actualDigest ~= expectedLogicalDigest
        error("sixgr:truth:FrozenDLLogicalPrecoderAuthorityMismatch", ...
            ['Frozen DL logical precoder authority diverged at stage ''%s'': ' ...
            '%s digest ''%s'' does not match PHYGrant digest ''%s''.'], ...
            char(string(stage)), char(paths(pathIdx)), char(actualDigest), ...
            char(expectedLogicalDigest));
    end
end

if logical(sixgr.util.structGet(prec, "HybridElementDomainApplied", false))
    expectedHybrid = double(sixgr.util.structGet(prec, "HybridElementToPortMatrix", []));
    actualHybrid = double(sixgr.util.structGet(cfgOut, ...
        "phy.pdsch.hybridElementToPortMatrix", []));
    if isempty(expectedHybrid) || isempty(actualHybrid) || ...
            string(sixgr.phy.mimo.MatrixContract.digest(actualHybrid)) ~= ...
            string(sixgr.phy.mimo.MatrixContract.digest(expectedHybrid))
        error("sixgr:truth:FrozenDLHybridArchitectureAuthorityMismatch", ...
            "Frozen DL hybrid RF architecture diverged at stage '%s'.", ...
            char(string(stage)));
    end
end

physicalMatrix = double(sixgr.util.structGet(prec, "MatrixPhysicalPorts", ...
    sixgr.util.structGet(prec, "Matrix", [])));
computedPhysicalDigest = string(sixgr.phy.mimo.MatrixContract.digest(physicalMatrix));
expectedPhysicalDigest = string(sixgr.util.structGet(prec, ...
    "SelectedMatrixSHA256", computedPhysicalDigest));
if isempty(physicalMatrix) || expectedPhysicalDigest ~= computedPhysicalDigest
    error("sixgr:truth:FrozenDLPhysicalPrecoderAuthorityMismatch", ...
        ['Frozen DL PHYGrant at stage ''%s'' carries physical digest ''%s'', ' ...
        'but its physical matrix hashes to ''%s''.'], ...
        char(string(stage)), char(expectedPhysicalDigest), ...
        char(computedPhysicalDigest));
end
actualPhysicalDigest = string(sixgr.util.structGet(cfgOut, ...
    "phy.pdsch.selectedPrecoderSHA256", ""));
if strlength(expectedPhysicalDigest) == 0 || actualPhysicalDigest ~= expectedPhysicalDigest
    error("sixgr:truth:FrozenDLPhysicalPrecoderAuthorityMismatch", ...
        ['Frozen DL physical precoder authority diverged at stage ''%s'': ' ...
        'runtime digest ''%s'', PHYGrant digest ''%s''.'], ...
        char(string(stage)), char(actualPhysicalDigest), char(expectedPhysicalDigest));
end

numRFChains = double(sixgr.util.structGet(grant, "NumRFChains", ...
    sixgr.util.structGet(phyGrant, "AntennaArchitecture.NumRFChains", NaN)));
if isscalar(numRFChains) && isfinite(numRFChains) && numRFChains >= 1
    cfgOut = sixgr.util.structSet(cfgOut, "phy.pdsch.numRFChains", round(numRFChains));
end
end
