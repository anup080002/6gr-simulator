function [admitted,cfg,decision]=resolveSharedPUCCHPowerAdmission(state,cfg,ue,resourceSlot)
% UE preparation admission, never gNB UCI outcome or measured link geometry.
% Re-select the configured PUCCH reference at the original decision clock;
% an applyUserContext PUSCH reference is not PUCCH power authority.
arguments
    state (1,1) struct
    cfg (1,1) struct
    ue (1,1) double {mustBeInteger,mustBePositive}
    resourceSlot (1,1) double {mustBeInteger,mustBePositive}
end
meta=sixgr.util.structGet(cfg,'lls6g.userContext',struct());
cellID=sixgr.util.structGet(state,'CurrentServingIdx',[]);
assert(ue<=state.NumUsers && numel(cellID)>=ue && ...
    localInteger(cellID(ue),1) && localInteger(state.CurrentSlot,1) && resourceSlot>=state.CurrentSlot && ...
    isequal(sixgr.util.structGet(meta,'UEIndex',[]),ue) && ...
    isequal(sixgr.util.structGet(meta,'RuntimeServingCell',[]),cellID(ue)) && ...
    isequal(sixgr.util.structGet(meta,'RuntimeCurrentSlot',[]),state.CurrentSlot) && ...
    string(sixgr.util.structGet(meta,'RuntimeCurrentDirection',""))=="UL", ...
    'sixgr:truth:PUCCHPowerAdmissionIdentity', ...
    'PUCCH admission requires the original bound UE, serving cell and current UL knowledge clock.');
required=sixgr.util.structGet(cfg,'validation.pucch_resources.power_control.require_measured_reference_rs',false);
assert((isnumeric(required)||islogical(required)) && isreal(required) && isscalar(required) && ...
    isfinite(required) && any(required==[0 1]), ...
    'sixgr:truth:PUCCHPowerAdmissionConfiguration','Measured PUCCH power policy must be explicitly binary.');
required=logical(required) && ~sixgr.rf.isNormalizedFixedSNRPowerReference(cfg);
knowledgeSlot=state.CurrentSlot;
if string(sixgr.util.structGet(state,'RuntimeViewMode','execution'))=="future_ul_grant_planning"
    knowledgeSlot=sixgr.util.structGet(state,'PlanningDecisionSlot',NaN);
end
assert(localInteger(knowledgeSlot,1) && knowledgeSlot<=state.CurrentSlot, ...
    'sixgr:truth:PUCCHPowerAdmissionIdentity','Retain the original non-future knowledge slot.');
decision=table(ue,double(cellID(ue)),double(knowledgeSlot),resourceSlot,required,true, ...
    "not_required_by_applied_power_mode","prepare_PUCCH", ...
    "",NaN,NaN,"",NaN,NaN,NaN, ...
    "original_PUCCH_reference_preparation_admission","preparation_admission_not_PHY_execution", ...
    'VariableNames',{'UEIndex','ServingCell','DecisionSlot','PUCCHResourceSlot', ...
    'MeasuredPowerReferenceRequired','PreparationAdmitted','PowerReferenceStatus','Action', ...
    'PowerReferenceRS','PowerReferenceSignalID','MaximumPowerReferenceAgeSlots', ...
    'PowerReferenceMeasurementID','PowerReferenceProducerSlot','PowerReferenceAvailableSlot', ...
    'MeasuredPathloss_dB','Source','EvidenceClass'});
admitted=true;
decision.PathlossReferenceLifetime="not_required_by_applied_power_mode";
decision.ReferenceLifecycleStatus="not_required_by_applied_power_mode";
if ~required, return; end
configured=sixgr.phy.refsig.resolveConfiguredPathlossReference(cfg,"PUCCH");
assert(configured.Available && configured.SignalType=="SSB", ...
    'sixgr:truth:PUCCHPowerAdmissionConfiguration', ...
    'Required shared PUCCH power currently needs a configured SSB with decoded common reference power; CSI-RS signalled power is not implemented.');
referenceID=sixgr.util.structGet(cfg,'validation.pucch_resources.power_control.pathloss_reference_rs_id',[]);
assert(localInteger(referenceID,0) && referenceID==configured.PathlossReferenceRSId, ...
    'sixgr:truth:PUCCHPowerAdmissionConfiguration', ...
    'PUCCH power and its active spatial relation must bind the same pathloss-reference identity.');
view=state;
if resourceSlot>state.CurrentSlot
    view=sixgr.truth.CoupledTruthRuntime.futureULPlanningView(state,resourceSlot);
end
[cfg,reference]=sixgr.truth.bindSharedSSBPowerReference( ...
    cfg,view,ue,resourceSlot,configured.ReferenceSignalId,"PUCCH");
assert(islogical(reference.ReferenceUsable) && isscalar(reference.ReferenceUsable), ...
    'sixgr:truth:PUCCHPowerAdmissionReference','Keep the original causal reference decision.');
admitted=reference.ReferenceUsable;
if ~admitted
    allowed=["no_measurements","no_matching_measurement","future_measurement_not_available", ...
        "stale","no_available_decoded_sib1_power","reference_lifecycle_unavailable"];
    assert(any(string(reference.Status)==allowed),'sixgr:truth:PUCCHPowerAdmissionUnavailableReason', ...
        'Only operational absence/staleness can defer PUCCH; configuration/integrity errors remain failures.');
    decision.Action="defer_PUCCH_unavailable_measured_power_reference";
end
decision.PreparationAdmitted=admitted;
decision.DecisionSlot=reference.KnowledgeSlot;
decision.PowerReferenceStatus=string(reference.Status);
decision.PowerReferenceRS=configured.ReferenceIdentity;
decision.PowerReferenceSignalID=configured.ReferenceSignalId;
decision.MaximumPowerReferenceAgeSlots=reference.MaximumAgeSlots;
decision.PathlossReferenceLifetime=reference.PathlossReferenceLifetime;
decision.ReferenceLifecycleStatus=reference.ReferenceLifecycleStatus;
decision.PowerReferenceMeasurementID=string(reference.MeasurementId);
decision.PowerReferenceProducerSlot=reference.ProducerSlot;
decision.PowerReferenceAvailableSlot=reference.AvailableSlot;
decision.MeasuredPathloss_dB=reference.Pathloss_dB;
end

function tf=localInteger(value,minimum)
tf=isnumeric(value) && isreal(value) && isscalar(value) && isfinite(value) && ...
    value>=minimum && value==fix(value) && value<=flintmax;
end
