function [cfg,installation]=resolveSRSCurrentInstallation(cfg,installation)
% Resolve CURRENT runtime endpoint ownership against the current catalog.
% This descriptor is built from runtime installation, never accepted SRS.
% Only configured identities/basis are carried; no H, SINR or receiver data.
fields={'Version','Source','UEIndex','RNTI','ServingCell','NCellID', ...
    'ConfigurationEpoch','ReceiverNumElements','ReceiverPortToElementMatrix'};
assert(isstruct(installation) && isscalar(installation) && all(isfield(installation,fields)) && ...
    string(installation.Version)=="current_srs_installation/v1" && ...
    string(installation.Source)=="current_runtime_endpoint_installation", ...
    'sixgr:truth:InvalidSRSCurrentInstallation','Require current installed endpoint authority.');
validateattributes([installation.UEIndex installation.RNTI installation.ServingCell], ...
    {'numeric'},{'real','finite','integer','positive'});
validateattributes(installation.NCellID,{'numeric'},{'real','scalar','finite','integer','>=',0,'<=',1007});
validateattributes(installation.ConfigurationEpoch,{'numeric'},{'real','scalar','finite','integer','nonnegative'});
assert(isequal(double(sixgr.util.structGet(cfg,'rf.configurationEpoch',NaN)), ...
    double(installation.ConfigurationEpoch)), ...
    'sixgr:truth:SRSCurrentInstallationMismatch','A retired runtime installation cannot replace the current epoch.');
matrix=installation.ReceiverPortToElementMatrix;
assert(isnumeric(matrix) && ismatrix(matrix) && ~isempty(matrix) && ...
    all(isfinite(matrix),'all') && size(matrix,1)==installation.ReceiverNumElements, ...
    'sixgr:truth:InvalidSRSCurrentInstallation','Retain the actual installed receiver spatial basis.');
cfg.phy.carrier.NCellID=double(installation.NCellID);
cfg=sixgr.phy.srs.bindConfiguredUEFrequencyResource(cfg,installation.UEIndex, ...
    installation.RNTI,installation.ServingCell);
cfg=sixgr.util.structSet(cfg,'lls6g.userContext.RuntimeServingBSAntenna', ...
    struct('NumElements',installation.ReceiverNumElements,'PortToElementMatrix',matrix));
id=sixgr.truth.srsConfigurationContextID(cfg,installation.ConfigurationEpoch, ...
    installation.UEIndex,installation.ServingCell);
if isfield(installation,'ConfigurationContextID')
    assert(string(installation.ConfigurationContextID)==id, ...
        'sixgr:truth:SRSCurrentInstallationMismatch', ...
        'The current catalog no longer matches the scheduler installation snapshot.');
end
installation.ConfigurationContextID=id;
end
