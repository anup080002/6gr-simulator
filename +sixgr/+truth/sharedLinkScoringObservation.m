function [reference,evidence,channelReferences]=sharedLinkScoringObservation(planes,prepared,planeID)
% Independent effective-link pilot reference, never a receiver input.
ids=string({planes.ReceiverID}); k=find(ids==string(planeID));
assert(isscalar(k),'sixgr:truth:MissingSharedScoringPlane','One complete independently observed link plane is required.');
reference=planes(k).Observation;
if isstruct(prepared) && string(sixgr.util.structGet(prepared,'ExecutionStage',""))=="trs_waveform_prepared_not_received"
    assert(reference.isComplete() && reference.SampleRateHz==prepared.SampleRateHz && ...
        reference.StartSample==prepared.TransmitStartSample && ...
        reference.EndSampleExclusive==prepared.TransmitStartSample+prepared.NumSamples, ...
        'sixgr:truth:TRSScoringObservationMismatch','Scoring must cover the prepared TRS observation.');
elseif isa(prepared,'sixgr.link.PreparedDataTransmission')
    prepared.readObservation(reference,prepared.RequestBinding.PHYGrant.AntennaArchitecture.NumRxAntennas,"receiver");
else
    prepared.readObservation(reference,"receiver");
end
post=planes(endsWith(ids,':post_rf')).Observation;
assert(reference.StartSample==post.StartSample && reference.EndSampleExclusive==post.EndSampleExclusive, ...
    'sixgr:truth:SharedScoringWindowMismatch','Scoring and received samples must have identical physical bounds.');
segments=planes(k).Segments;
txID=extractBefore(ids(endsWith(ids,':tx')),':tx');
rxID=extractBefore(ids(endsWith(ids,':post_rf')),':post_rf');
intervals=zeros(numel(segments),2); active=false(numel(segments),1); linkIDs=strings(numel(segments),1);
channelReferences=cell(0,1);
timingReplays=cell(0,1);
for n=1:numel(segments)
    segment=segments{n}; entries=segment.Execution.ScoringPlanes;
    entry=entries(string({entries.ID})==string(planeID));
    assert(isscalar(entry) && entry.RX==rxID && ...
        entry.Source=="actual_link_contribution_after_tx_rf_channel_loss_before_sum_noise_rx_rf" && ...
        (~entry.Active || entry.TX==txID), ...
        'sixgr:truth:SharedScoringProvenanceMismatch','Scoring must belong to the actually executed serving link.');
    intervals(n,:)=[segment.StartSample segment.EndSampleExclusive];
    active(n)=entry.Active; linkIDs(n)=entry.LinkID;
    if entry.Active
        executedLinks=segment.Execution.Links;
        executedLink=executedLinks(string({executedLinks.ID})==entry.LinkID & ...
            string({executedLinks.TX})==txID & string({executedLinks.RX})==rxID);
        assert(isscalar(executedLink), ...
            'sixgr:truth:MissingSharedTimingTruth', ...
            'The active serving link must retain its executed channel timing metadata.');
        timingReplays{end+1,1}=executedLink.Replay; %#ok<AGROW>
    end
    if isfield(segment.Execution,'ChannelReferences')
        captures=segment.Execution.ChannelReferences;
        captures=captures(string({captures.LinkID})==entry.LinkID & ...
            string({captures.TX})==txID & string({captures.RX})==rxID);
        for capture=captures
            r=capture.Reference;
            assert(all(isfield(r,{'ObservationStartSample','ObservationEndSampleExclusive'})), ...
                'sixgr:truth:UnscopedSharedChannelReference', ...
                'Every coefficient capture must identify its requested observation window.');
            if r.ObservationStartSample~=reference.StartSample || ...
                    r.ObservationEndSampleExclusive~=reference.EndSampleExclusive
                % An adjacent transmission can share this processor segment
                % but must not contribute duplicate or out-of-window gains.
                continue;
            end
            assert(entry.Active && sixgr.channel.isAppliedChannelReference(r) && ...
                ~r.ReceiverEstimatorInput && r.AdditionalChannelExecutions==0 && ...
                r.StartSample>=reference.StartSample && r.EndSampleExclusive<=reference.EndSampleExclusive && ...
                size(r.PathGains,1)==r.EndSampleExclusive-r.StartSample, ...
                'sixgr:truth:InvalidSharedChannelReference','Retain only the actual serving-link interval and full applied coefficients.');
            channelReferences{end+1,1}=capture; %#ok<AGROW>
        end
    end
end
captureIntervals=zeros(0,2);
activeIntervals=intervals(active,:);
activeIntervals(:,1)=max(activeIntervals(:,1),reference.StartSample);
activeIntervals(:,2)=min(activeIntervals(:,2),reference.EndSampleExclusive);
inactiveIntervals=intervals(~active,:);
inactiveIntervals(:,1)=max(inactiveIntervals(:,1),reference.StartSample);
inactiveIntervals(:,2)=min(inactiveIntervals(:,2),reference.EndSampleExclusive);
if ~isempty(channelReferences)
    bounds=cell2mat(cellfun(@(c)[c.Reference.StartSample c.Reference.EndSampleExclusive], ...
        channelReferences,'UniformOutput',false));
    % A TDD observation may extend into a reversed-link interval. There is
    % no channel execution toward this RX then: retain that exclusion, not
    % invented coefficients or another execution of the fading object.
    assert(isequal(bounds,activeIntervals), ...
        'sixgr:truth:IncompleteSharedChannelReference', ...
        'Captured coefficients must cover every actual direction-active link segment exactly once.');
    captureIntervals=bounds;
end
assert(~isempty(segments) && any(active) && numel(unique(linkIDs))==1 && ...
    intervals(1,1)<=reference.StartSample && intervals(end,2)>=reference.EndSampleExclusive && ...
    all(intervals(2:end,1)==intervals(1:end-1,2)), ...
    'sixgr:truth:IncompleteSharedScoringExecution','Do not fill gaps or replace an absent desired-link execution.');
evidence=struct('Source',"actual_executed_link_contribution",'Scope', ...
    "effective_pilot_response_includes_actual_tx_rf_not_isolated_pure_channel_matrix", ...
    'LinkID',linkIDs(1),'TransmitterID',txID,'ReceiverID',rxID, ...
    'StartSample',reference.StartSample,'EndSampleExclusive',reference.EndSampleExclusive, ...
    'Intervals',intervals,'LinkActive',active,'ReceiverEstimatorInput',false, ...
    'ChannelReferenceCoverageComplete',~isempty(channelReferences), ...
    'ChannelReferenceScope',"actual_direction_active_link_intervals_within_receive_window", ...
    'ChannelReferenceIntervals',captureIntervals, ...
    'ChannelReferenceInactiveIntervals',inactiveIntervals, ...
    'ChannelMatrixReference',false, ...
    'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0,'ReferenceGainFitted',false);
if ~isempty(timingReplays)
    requiredTimingFields={'RuntimeChannelFilterDelay_samples', ...
        'RuntimeChannelMinimumPathDelay_samples', ...
        'RuntimeChannelExpectedEarliestArrivalDelay_samples', ...
        'RuntimeChannelTimingTruthSource'};
    assert(all(cellfun(@(v)all(isfield(v,requiredTimingFields)),timingReplays)), ...
        'sixgr:truth:IncompleteSharedTimingTruth', ...
        'Every active serving-link execution must retain filter and path-delay timing truth.');
    for field=requiredTimingFields
        values=cellfun(@(v)v.(field{1}),timingReplays,'UniformOutput',false);
        assert(all(cellfun(@(v)isequaln(v,values{1}),values)), ...
            'sixgr:truth:TimeVaryingSharedTimingTruth', ...
            'Channel timing truth must remain invariant across one receive observation.');
        evidence.(field{1})=values{1};
    end
end
end
