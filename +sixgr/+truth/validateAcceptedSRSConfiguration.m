function validateAcceptedSRSConfiguration(cfg,decision)
% Compare retained producer configuration to the current installed context.
% No measured channel/quality enters UE precoder selection through this
% metadata. SRI/TPMI/rank still belong to independently received control.
domain=string(sixgr.util.structGet(decision,'MeasurementClockDomain',"slot_only"));
id=string(sixgr.util.structGet(decision,'SRSConfigurationContextID',""));
ports=sixgr.util.structGet(decision,'SRSNumPorts',NaN);
bound=strlength(id)>0;
assert(isscalar(domain) && isscalar(bound) && ~ismissing(id) && ...
    (domain~="shared_receiver_sample_clock/v1" || bound), ...
    'sixgr:truth:MissingAcceptedSRSConfiguration', ...
    'Shared accepted SRS must retain the actual producer configuration identity.');
assert(isnumeric(ports) && isreal(ports) && isscalar(ports), ...
    'sixgr:truth:AcceptedSRSConfigurationMismatch','Sounded port count must be one numeric value.');
if ~bound && isnan(ports), return; end % Declared slot-only component boundary.
strict=sixgr.phy.srs.buildSRSConfigFromScenario(cfg);
assert(isnumeric(ports) && isreal(ports) && isscalar(ports) && ...
    isfinite(ports) && ports==double(strict.ToolboxSRS.NumSRSPorts), ...
    'sixgr:truth:AcceptedSRSConfigurationMismatch', ...
    'Accepted SRS ports must match the installed sounding resource.');
if ~bound, return; end
assert(string(sixgr.util.structGet(decision,'SRSConfigurationContextVersion',""))== ...
    "srs_configuration_context/v1",'sixgr:truth:MissingAcceptedSRSConfiguration', ...
    'A phase-history or unversioned hash is not an accepted-SRS configuration identity.');
epoch=sixgr.util.structGet(decision,'SRSConfigurationEpoch',NaN);
assert(isnumeric(epoch) && isreal(epoch) && isscalar(epoch) && ...
    isfinite(epoch) && epoch>=0 && epoch==fix(epoch), ...
    'sixgr:truth:MissingAcceptedSRSConfiguration', ...
    'A retained SRS configuration identity requires its original configuration epoch.');
assert(isequal(double(epoch),double(sixgr.util.structGet(cfg,'rf.configurationEpoch',NaN))), ...
    'sixgr:truth:AcceptedSRSConfigurationMismatch', ...
    'An accepted source cannot relabel its retired epoch as the current installation.');
if domain=="shared_receiver_sample_clock/v1"
    assert(isequal(epoch,sixgr.util.structGet(decision,'MeasurementClockEpoch',NaN)), ...
        'sixgr:truth:AcceptedSRSConfigurationMismatch','Shared producer configuration and receiver epochs must agree.');
end
installed=sixgr.truth.srsConfigurationContextID(cfg,epoch,decision.TargetId,decision.ServingCell);
assert(id==installed,'sixgr:truth:AcceptedSRSConfigurationMismatch', ...
    'Accepted SRS cannot be reused after its installed resource, carrier, ports or spatial basis changes.');
end
