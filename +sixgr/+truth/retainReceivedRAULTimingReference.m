function state=retainReceivedRAULTimingReference(state,ue,cfg,result,observation,availableAt)
% Bridge an accepted SetupComplete DM-RS measurement to connected UL RX.
% Msg3 remains a temporary-identity observation, never renamed as connected.
validateattributes(ue,{'numeric'},{'scalar','real','finite','integer','positive','<=',state.NumUsers});
validateattributes(availableAt,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
assert(isstruct(result) && isscalar(result), ...
    'sixgr:truth:InvalidRAULTimingResult','Retain the original completed RA result.');
if ~isfield(result,'SetupCompleteRx') || isempty(fieldnames(result.SetupCompleteRx)), return; end
rx=result.SetupCompleteRx;
for name=["RACompleted","SetupCompleteReceiverOk","RRCSetupCompleteCRC","RRCSetupCompleteDecoded","RRCConnected"]
    value=sixgr.util.structGet(result,name,[]);
    assert((islogical(value)||isnumeric(value)) && isscalar(value) && isreal(value) && ...
        isfinite(value) && any(value==[0 1]), ...
        'sixgr:truth:InvalidRAULTimingResult','RA outcome %s must be an original boolean.',name);
    if ~value, return; end
end
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && isscalar(observation) && ...
    availableAt>=observation.EndSampleExclusive, ...
    'sixgr:truth:FutureRAULTimingReference','Complete the actual UL capture before publishing its clock.');
cellID=state.CurrentServingIdx(ue);
rnti=sixgr.truth.CoupledRadioIdentity.resolve(state,ue,cellID);
assert(isfield(rx,'ReceivedULTimingReceipt') && ...
    rx.ReceivedULTimingReceipt.Stage=="RRCSetupComplete" && ...
    result.FinalCRNTI==rnti && rx.ReceivedULTimingReceipt.RNTI==rnti, ...
    'sixgr:truth:RAULTimingIdentityMismatch','Require accepted final C-RNTI, not a renamed provisional Msg3 clock.');
rows=result.RuntimeStageRows;
hit=string(rows.StageName)=="RRCSetupComplete";
assert(nnz(hit)==1,'sixgr:truth:RAULTimingStageMismatch','Retain exactly one actual SetupComplete receiver stage.');
row=rows(hit,:); r=rx.ReceivedULTimingReceipt;
assert(row.UEId==ue && row.CellId==r.NCellID && ...
    cfg.lls6g.userContext.RuntimeServingCell==cellID && ...
    row.StageSlot==r.AbsoluteSlot0 && row.Direction=="UL" && ...
    row.ObservationStartSample==observation.StartSample && ...
    row.ObservationEndSampleExclusive==observation.EndSampleExclusive && ...
    row.ObservationSampleRateHz==observation.SampleRateHz && ...
    row.RxSampleCount==observation.EndSampleExclusive-observation.StartSample && ...
    row.RuntimeStageWaveformUsed && ~row.SelfLoopWaveformUsed, ...
    'sixgr:truth:RAULTimingStageMismatch','Join the original stage identity, capture extent and received input.');
contexts=state.ConnectedULTimingByUE;
assert(numel(contexts)>=ue && ~isempty(contexts{ue}), ...
    'sixgr:truth:RAULTimingTAGRequired','A received initial TAG must already own this connected UE.');
tag=contexts{ue};
assert(tag.TimingAdvanceAvailableAtSample<=observation.StartSample && ...
    availableAt<tag.TimeAlignmentExpirySampleExclusive && ...
    tag.ReceivedRARTiming.SampleRateHz==observation.SampleRateHz && ...
    r.AbsoluteSlot0>=tag.Application.EffectiveULSlot0Based && ...
    tag.DLReference.NCellID==r.NCellID && ...
    isequaln(cfg.SharedULTimingContext.DLReference,tag.DLReference) && ...
    isequaln(cfg.SharedULTimingContext.Offset,tag.Offset) && ...
    result.TimingAdvanceCommand==tag.ReceivedRARTiming.Command && ...
    result.TimingAdvanceNTA_Tc==tag.ReceivedRARTiming.NTA_Tc && ...
    result.TimingAdvanceSampleRate_Hz==tag.ReceivedRARTiming.SampleRateHz, ...
    'sixgr:truth:RAULTimingTAGMismatch','Do not cross received TAG, serving-cell or sample-clock authority.');
cfg.phy.pusch.RNTI=rnti;
cfg.SharedULTimingContext=tag;
reference=sixgr.phy.sync.ReceivedULTimingReference(rx,observation,rx.ReceiveTiming,cfg);
state=sixgr.truth.storeReceivedULTimingReference(state,ue,reference);
end
