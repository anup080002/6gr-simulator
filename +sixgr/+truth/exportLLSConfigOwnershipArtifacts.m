function value = localLookupTableValue(T, fieldName, selector)
value = "";
if ~(istable(T) && ~isempty(T) && ismember(string(fieldName), string(T.Properties.VariableNames)))
    return;
end
slice = T;
selector = strtrim(string(selector));

if contains(lower(selector), "direction=") && ismember("Direction", string(slice.Properties.VariableNames))
    dirTok = extractAfter(lower(selector), "direction=");
    dirTok = extractBefore(dirTok + ";", ";");
    mask = strcmpi(strtrim(string(slice.Direction)), strtrim(string(dirTok)));
    slice = slice(mask, :);
end

if contains(lower(selector), "non_warmup") && ismember("IsWarmupFrame", string(slice.Properties.VariableNames))
    warmMask = logical(slice.IsWarmupFrame);
    if any(~warmMask)
        slice = slice(~warmMask, :);
    end
end

if isempty(slice)
    return;
end

fieldName = char(fieldName);
if contains(lower(selector), "last")
    rowOrder = height(slice):-1:1;
else
    rowOrder = 1:height(slice);
end
for rowIdx = rowOrder
    candidate = localScalarToString(slice{rowIdx, fieldName});
    if strlength(candidate) > 0
        value = candidate;
        return;
    end
end
end

