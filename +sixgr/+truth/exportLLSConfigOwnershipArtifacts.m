function [status, note] = localDetermineRoundtripStatus(ctx, entry, browserSubmitted, overlayValue, resolvedValue, dbValue, runtimeEvidence, browserDisplayed)
noteParts = strings(0, 1);
mismatch = false;

if strlength(overlayValue) > 0
    [sameValue, comparisonNote] = localRoundtripValuesEqual(entry, browserSubmitted, overlayValue);
    if strlength(browserSubmitted) > 0 && ~sameValue
        mismatch = true;
        noteParts(end+1, 1) = "overlay_does_not_match_browser_submission"; %#ok<AGROW>
    elseif strlength(comparisonNote) > 0
        noteParts(end+1, 1) = comparisonNote; %#ok<AGROW>
    end
else
    noteParts(end+1, 1) = "overlay_inherited_from_base"; %#ok<AGROW>
end

if strlength(browserSubmitted) > 0 && strlength(resolvedValue) > 0 && ~logical(entry.RuntimeDerived)
    [sameValue, comparisonNote] = localRoundtripValuesEqual(entry, browserSubmitted, resolvedValue);
    if ~sameValue
        mismatch = true;
        noteParts(end+1, 1) = "resolved_runtime_value_differs_from_browser_submission"; %#ok<AGROW>
    elseif strlength(comparisonNote) > 0
        noteParts(end+1, 1) = comparisonNote; %#ok<AGROW>
    end
end

if strlength(dbValue) > 0
    [sameValue, comparisonNote] = localRoundtripValuesEqual(entry, dbValue, resolvedValue);
    if strlength(resolvedValue) > 0 && ~sameValue
        mismatch = true;
        noteParts(end+1, 1) = "db_snapshot_differs_from_resolved_runtime_value"; %#ok<AGROW>
    elseif strlength(comparisonNote) > 0
        noteParts(end+1, 1) = comparisonNote; %#ok<AGROW>
    end
else
    noteParts(end+1, 1) = "db_snapshot_unavailable"; %#ok<AGROW>
end

if strlength(runtimeEvidence) > 0 && strlength(resolvedValue) > 0
    [sameValue, comparisonNote] = localRoundtripValuesEqual(entry, runtimeEvidence, resolvedValue);
    if ~sameValue
        noteParts(end+1, 1) = "runtime_evidence_diverges_from_resolved_runtime_value"; %#ok<AGROW>
    elseif strlength(comparisonNote) > 0
        noteParts(end+1, 1) = comparisonNote; %#ok<AGROW>
    end
end

if strlength(browserDisplayed) > 0 && strlength(resolvedValue) > 0
    [sameValue, comparisonNote] = localRoundtripValuesEqual(entry, browserDisplayed, resolvedValue);
    if ~sameValue
        mismatch = true;
        noteParts(end+1, 1) = "browser_display_value_differs_from_exported_runtime_value"; %#ok<AGROW>
    elseif strlength(comparisonNote) > 0
        noteParts(end+1, 1) = comparisonNote; %#ok<AGROW>
    end
end

if mismatch
    status = "mismatch";
elseif logical(entry.RuntimeDerived)
    if strlength(dbValue) > 0
        status = "consistent_runtime_derived";
    else
        status = "consistent_runtime_derived_db_unavailable";
    end
elseif strlength(overlayValue) == 0 && logical(ctx.BrowserOwnedRun)
    if strlength(dbValue) > 0
        status = "consistent_inherited_from_base";
    else
        status = "consistent_inherited_from_base_db_unavailable";
    end
elseif strlength(dbValue) == 0
    status = "consistent_db_unavailable";
else
    status = "consistent";
end

note = strjoin(noteParts, "; ");
end

function [tf, note] = localRoundtripValuesEqual(entry, a, b)
note = "";
ta = strtrim(localScalarToString(a));
tb = strtrim(localScalarToString(b));
if strlength(ta) == 0 && strlength(tb) == 0
    tf = true;
    return;
end
na = str2double(ta);
nb = str2double(tb);
if isfinite(na) && isfinite(nb)
    tf = abs(na - nb) < 1e-9;
    return;
end
ca = localComparableRoundtripToken(string(entry.ParameterName), ta);
cb = localComparableRoundtripToken(string(entry.ParameterName), tb);
tf = strcmpi(ca, cb);
if tf && ~strcmpi(ta, tb)
    note = "semantic_alias_resolved_by_runtime_normalizer";
end
end

function token = localComparableRoundtripToken(parameterName, value)
token = lower(strtrim(localScalarToString(value)));
token = replace(token, "-", "_");
token = replace(token, " ", "_");
switch string(parameterName)
    case "deployment_topology.layout_type"
        if ismember(token, ["single_pair","single_link","singlelink","single","link_pair"])
            token = "indoor_grid";
        elseif contains(token, "hex")
            token = "hex_grid";
        elseif contains(token, "indoor")
            token = "indoor_grid";
        elseif contains(token, "rect") || token == "grid"
            token = "rect_grid";
        end
    case "mobility.trajectory_model"
        if ismember(token, ["line","linear","fixed","fixed_heading","straight","straightline","straight_line"])
            token = "straightline";
        elseif ismember(token, ["randomwaypoint","random_waypoint","waypoint"])
            token = "randomwaypoint";
        elseif ismember(token, ["zigzag","zig_zag","zigzag_line","zig_zag_line"])
            token = "zigzag";
        elseif ismember(token, ["trajectory_trace","trace"])
            token = "trace";
        end
    case "traffic.model"
        if ismember(token, ["full_buffer","fullbuffer","full"])
            token = "fullbuffer";
        end
end
end

function T = localBuildBrowserRuntimeDBConsistency(roundtripT)
if isempty(roundtripT)
    T = localEmptyBrowserRuntimeDBConsistencyTable();
    return;
end

rows = repmat(localBrowserConsistencyPrototype(), height(roundtripT), 1);
for i = 1:height(roundtripT)
    dbValue = string(roundtripT.DBSnapshotValue(i));
    exportValue = string(roundtripT.ExportedCSVValue(i));
    browserValue = string(roundtripT.BrowserDisplayedValue(i));
    roundtripStatus = "";
    if istable(roundtripT) && ismember("ConsistencyStatus", string(roundtripT.Properties.VariableNames))
        roundtripStatus = lower(strtrim(string(roundtripT.ConsistencyStatus(i))));
    end
    dbSource = "";
    if istable(roundtripT) && ismember("DBSnapshotSource", string(roundtripT.Properties.VariableNames))
        dbSource = lower(strtrim(string(roundtripT.DBSnapshotSource(i))));
    end
    runtimeDerived = false;
    if istable(roundtripT) && ismember("RuntimeDerived", string(roundtripT.Properties.VariableNames))
        runtimeDerived = logical(roundtripT.RuntimeDerived(i));
    end
    if strlength(dbValue) == 0 && startsWith(roundtripStatus, "consistent")
        status = string(roundtripT.ConsistencyStatus(i));
    elseif strlength(dbValue) == 0 && runtimeDerived
        status = "consistent_runtime_derived_db_unavailable";
    elseif strlength(dbValue) == 0 && dbSource == "db_inactive"
        status = "consistent_db_inactive";
    elseif strlength(dbValue) == 0
        status = "db_snapshot_unavailable";
    elseif localStringValuesEqual(dbValue, exportValue) && localStringValuesEqual(exportValue, browserValue)
        status = "consistent";
    else
        status = "mismatch";
    end

    rows(i).ParameterName = string(roundtripT.ParameterName(i));
    rows(i).Category = string(roundtripT.Category(i));
    rows(i).DBSnapshotValue = dbValue;
    rows(i).DBLogicalPath = "sim_runs.config_json";
    rows(i).ExportedCSVLogicalPath = "reports/csv/config_roundtrip_verification.csv";
    rows(i).ExportedCSVValue = exportValue;
    rows(i).BrowserPayloadField = "runtime_context.roundtrip_artifacts.config_roundtrip_verification";
    rows(i).BrowserDisplayedValue = browserValue;
    rows(i).ConsistencyStatus = status;
    rows(i).BrowserVisible = true;
    rows(i).RuntimeConsumer = string(roundtripT.RuntimeConsumer(i));
    rows(i).ConsistencyNotes = string(roundtripT.ConsistencyNotes(i));
end
T = struct2table(rows);
end

