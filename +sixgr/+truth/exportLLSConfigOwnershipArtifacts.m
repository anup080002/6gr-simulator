end

function value = localResolveBrowserOverlaySubmittedValue(scfg, sourceFiles, baseStruct, scenarioPaths, browserSubmitted)
overlayPath = "";
if isa(scfg, "sixgr.lls6g.config.ScenarioConfig") && isprop(scfg, "ConfigPath")
    candidate = string(scfg.ConfigPath);
    if localIsBrowserOverlayPath(candidate)
        overlayPath = candidate;
    end
elseif isstruct(scfg)
    candidate = string(sixgr.util.structGet(scfg, "ConfigPath", ""));
    if localIsBrowserOverlayPath(candidate)
        overlayPath = candidate;
    end
end
if strlength(overlayPath) == 0
    overlayPath = localDetectBrowserOverlayPath("", sourceFiles);
end
value = localResolveOverlayValue(overlayPath, scenarioPaths);
if strlength(value) == 0 && isstruct(baseStruct) && ~isempty(fieldnames(baseStruct))
    baseValue = localResolveScenarioValue(baseStruct, scenarioPaths);
    if strlength(browserSubmitted) > 0 && ~localStringValuesEqual(browserSubmitted, baseValue)
        value = browserSubmitted;
    end
end
end

function value = localResolveOverlayValue(overlayPath, scenarioPaths)
value = "";
if strlength(string(overlayPath)) == 0
    return;
end
overlayStruct = localReadOverlayStruct(overlayPath);
if isempty(fieldnames(overlayStruct))
    return;
end
paths = string(scenarioPaths);
for i = 1:numel(paths)
    [candidate, found] = localTryGetNestedValue(overlayStruct, paths(i));
    if ~found
        continue;
    end
    value = localScalarToString(candidate);
    if strlength(value) > 0
        return;
    end
end
end

