function txt = localScalarToString(value)
txt = "";
if isempty(value)
    return;
end
if iscell(value)
    if isempty(value)
        return;
    end
    txt = localScalarToString(value{1});
    return;
end
if isstring(value)
    if isempty(value)
        return;
    end
    if numel(value) == 1
        txt = strtrim(value);
    else
        txt = strjoin(strtrim(value(:).'), "|");
    end
    return;
end
if ischar(value)
    txt = strtrim(string(value));
    return;
end
if islogical(value)
    if isscalar(value)
        txt = string(double(value));
    else
        txt = strjoin(string(double(value(:).')), "|");
    end
    return;
end
if isnumeric(value)
    if isscalar(value)
        txt = localValueToString(double(value));
    else
        vals = double(value(:).');
        parts = strings(1, numel(vals));
        for i = 1:numel(vals)
            parts(i) = localValueToString(vals(i));
        end
        txt = strjoin(parts, "|");
    end
    return;
end
try
    txt = string(value);
catch
    txt = "";
end
end

function txt = localValueToString(value)
if isempty(value) || (isscalar(value) && isnumeric(value) && ~isfinite(value))
    txt = "";
    return;
end
if abs(value - round(value)) < 1e-12
    txt = string(round(value));
else
    txt = string(sprintf('%.12g', double(value)));
end
end

