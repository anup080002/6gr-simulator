function ctx = localBuildContext(runFolder, scfg, cfg, layout)
ctx = struct();
ctx.RunFolder = string(runFolder);
ctx.Layout = layout;
ctx.ScenarioConfig = scfg;
ctx.Config = cfg;
ctx.ScenarioStruct = localScenarioStruct(scfg);
ctx.ConfigPath = "";
if isa(scfg, "sixgr.lls6g.config.ScenarioConfig") && isprop(scfg, "ConfigPath")
    ctx.ConfigPath = string(scfg.ConfigPath);
elseif isstruct(scfg)
    ctx.ConfigPath = string(sixgr.util.structGet(scfg, "ConfigPath", ""));
end
if strlength(ctx.ConfigPath) == 0
    ctx.ConfigPath = string(sixgr.util.structGet(cfg, ...
        "lls6g.resolvedConfig.config_inheritance.provenance.config_path", ""));
end
ctx.SourceFiles = strings(0, 1);
if isa(scfg, "sixgr.lls6g.config.ScenarioConfig") && isprop(scfg, "SourceFiles")
    ctx.SourceFiles = string(scfg.SourceFiles(:));
elseif isstruct(scfg)
    ctx.SourceFiles = string(sixgr.util.structGet(scfg, "SourceFiles", strings(0, 1)));
end
if isempty(ctx.SourceFiles) || all(strlength(strtrim(ctx.SourceFiles)) == 0)
    ctx.SourceFiles = string(sixgr.util.structGet(cfg, ...
        "lls6g.resolvedConfig.config_inheritance.provenance.source_files", strings(0, 1)));
    ctx.SourceFiles = ctx.SourceFiles(:);
end
ctx.DBState = localGetDBState();
[ctx.DBRunID, ctx.DBConfigStruct] = localFetchDBConfigSnapshot(ctx.DBState, cfg, scfg);
ctx.SourceKind = localResolveConfigSourceKind(ctx.ScenarioStruct, ctx.Config, ctx.DBConfigStruct, ctx.ConfigPath, ctx.SourceFiles);
ctx.OverlayPath = localDetectBrowserOverlayPath(ctx.ConfigPath, ctx.SourceFiles, ctx.SourceKind);
ctx.OverlayStruct = localReadOverlayStruct(ctx.OverlayPath);
ctx.BrowserOwnedRun = ctx.SourceKind == "browser_runtime_overlay" || localIsBrowserOverlayPath(ctx.ConfigPath) || strlength(ctx.OverlayPath) > 0;
ctx.PreOverlayBaseStruct = localReadPreOverlayBaseStruct(ctx.OverlayPath, ctx.SourceFiles);

ctx.ScenarioSummary = localReadOptionalTable(fullfile(layout.ReportCSVDir, "scenario_summary.csv"));
ctx.RuntimeOperatingMode = localReadOptionalTable(fullfile(layout.ReportCSVDir, "runtime_operating_mode.csv"));
ctx.DeploymentReference = localReadOptionalTable(fullfile(layout.ReportCSVDir, "deployment_layout_reference.csv"));
ctx.ControlSummary = localReadOptionalTable(fullfile(layout.ReportCSVDir, "live_control_gating_summary.csv"));
ctx.ControlState = localReadOptionalTable(fullfile(layout.ReportCSVDir, "live_control_gating_state.csv"));
ctx.DLTrials = localReadOptionalTable(fullfile(layout.AirInterfaceCSVDir, "dl_pdsch_trials.csv"));
ctx.ULTrials = localReadOptionalTable(fullfile(layout.AirInterfaceCSVDir, "ul_pusch_trials.csv"));
ctx.DLGrants = localReadOptionalTable(fullfile(layout.PacketFlowCSVDir, "live_dl_scheduler_grants.csv"));
ctx.ULGrants = localReadOptionalTable(fullfile(layout.PacketFlowCSVDir, "live_ul_scheduler_grants.csv"));

end

function s = localScenarioStruct(scfg)
if isa(scfg, "sixgr.lls6g.config.ScenarioConfig")
    s = scfg.toStruct();
else
    s = scfg;
end
end

function overlayPath = localDetectBrowserOverlayPath(configPath, sourceFiles, sourceKind)
overlayPath = "";
configPath = string(configPath);
if nargin >= 3 && string(sourceKind) == "browser_runtime_overlay" && strlength(configPath) > 0
    overlayPath = configPath;
    return;
end
if localIsBrowserOverlayPath(configPath)
    overlayPath = configPath;
    return;
end
if isempty(sourceFiles)
    return;
end
for i = numel(sourceFiles):-1:1
    candidate = string(sourceFiles(i));
    if localIsBrowserOverlayPath(candidate)
        overlayPath = candidate;
        return;
    end
end
end

function kind = localResolveConfigSourceKind(scenarioStruct, cfg, dbStruct, configPath, sourceFiles)
kind = localFirstNonBlank( ...
    string(sixgr.util.structGet(scenarioStruct, "SourceKind", "")), ...
    string(sixgr.util.structGet(scenarioStruct, "meta.SourceKind", "")), ...
    string(sixgr.util.structGet(scenarioStruct, "config_inheritance.provenance.source_kind", "")), ...
    string(sixgr.util.structGet(cfg, "lls6g.resolvedConfig.config_inheritance.provenance.source_kind", "")), ...
    string(sixgr.util.structGet(dbStruct, "lls6g.configSourceKind", "")));
if strlength(kind) > 0
    return;
end
if localIsBrowserOverlayPath(configPath)
    kind = "browser_runtime_overlay";
    return;
end
for i = 1:numel(sourceFiles)
    if localIsBrowserOverlayPath(sourceFiles(i))
        kind = "browser_runtime_overlay";
        return;
    end
end
kind = "scenario_config_file";
end

function out = localFirstNonBlank(varargin)
out = "";
for i = 1:nargin
    candidate = string(varargin{i});
    if any(strlength(strtrim(candidate)) > 0)
        out = candidate(1);
        return;
    end
end
end

function tf = localIsBrowserOverlayPath(candidate)
candidate = string(candidate);
tf = false;
if strlength(candidate) == 0
    return;
end
[~, name, ext] = fileparts(char(candidate));
name = string(name);
ext = string(ext);
tf = startsWith(name, "__web_runtime_", "IgnoreCase", true) && any(strcmpi(ext, [".yaml",".yml",".json"]));
end

function overlayStruct = localReadOverlayStruct(overlayPath)
overlayStruct = struct();
if strlength(string(overlayPath)) == 0
    return;
end
try
    overlayRaw = fileread(char(string(overlayPath)));
    overlayStruct = jsondecode(overlayRaw);
catch
    try
        overlayStruct = sixgr.lls6g.config.readConfigFile(char(string(overlayPath)));
    catch
        overlayStruct = struct();
    end
end
if isfield(overlayStruct, "inherits")
    overlayStruct = rmfield(overlayStruct, "inherits");
end
end

function T = localReadOptionalTable(filePath)
T = table();
if exist(filePath, "file") ~= 2
    return;
end
try
    T = readtable(filePath, "VariableNamingRule", "preserve", "Delimiter", ",");
catch
    T = table();
end
end

function state = localGetDBState()
try
    state = sixgr.db.artifactStore("get_state");
catch
    state = struct();
end
end

function [runID, cfgStruct] = localFetchDBConfigSnapshot(state, cfg, scfg)
runID = NaN;
cfgStruct = struct();
conn = [];
if isstruct(state) && logical(sixgr.util.structGet(state, "Active", false))
    conn = sixgr.util.structGet(state, "Connection", []);
    runID = double(sixgr.util.structGet(state, "RunID", NaN));
end
try
    [runID, cfgStruct] = localQueryDBConfigSnapshot(conn, runID, cfg, scfg);
catch
    cfgStruct = struct();
end
end

function [runID, cfgStruct] = localQueryDBConfigSnapshot(conn, runID, cfg, scfg)
cfgStruct = struct();
cleanupConn = [];
if isempty(conn)
    backend = lower(string(sixgr.util.structGet(cfg, "outputs.storageBackend", "")));
    if backend ~= "mysql_web"
        return;
    end
    host = char(string(sixgr.util.structGet(cfg, "outputs.databaseHost", "localhost")));
    port = double(sixgr.util.structGet(cfg, "outputs.databasePort", 3306));
    schema = char(string(sixgr.util.structGet(cfg, "outputs.databaseSchema", "sixgr_results")));
    if strlength(string(getenv("MYSQL_USER"))) == 0 || strlength(string(getenv("MYSQL_PASSWORD"))) == 0
        return;
    end
    conn = sixgr.util.connectMySQLJDBC( ...
        Host=host, Port=port, Database=schema, Username=getenv("MYSQL_USER"), Password=getenv("MYSQL_PASSWORD"));
    cleanupConn = onCleanup(@() conn.close()); %#ok<NASGU>
end

if isfinite(runID)
    ps = conn.prepareStatement("SELECT run_id, config_json FROM sim_runs WHERE run_id=?");
    cleanupPs = onCleanup(@() ps.close()); %#ok<NASGU>
    ps.setLong(1, int64(runID));
else
    runTag = char(string(sixgr.util.structGet(cfg, "run.runTag", "")));
    if strlength(string(runTag)) == 0
        runTag = char(string(sixgr.util.structGet(scfg, "RunTag", "")));
    end
    if strlength(string(runTag)) == 0
        return;
    end
    ps = conn.prepareStatement([ ...
        "SELECT run_id, config_json FROM sim_runs " + ...
        "WHERE run_tag=? ORDER BY updated_utc DESC LIMIT 1"]);
    cleanupPs = onCleanup(@() ps.close()); %#ok<NASGU>
    ps.setString(1, runTag);
end
rs = ps.executeQuery();
cleanupRs = onCleanup(@() rs.close()); %#ok<NASGU>
if ~rs.next()
    return;
end
runID = double(rs.getLong(1));
raw = char(string(rs.getString(2)));
if strlength(string(raw)) > 0
    cfgStruct = localDecodeStoredJSON(raw);
end
end

function cfgStruct = localDecodeStoredJSON(raw)
cfgStruct = struct();
raw = char(string(raw));
if strlength(string(raw)) == 0
    return;
end
try
    cfgStruct = jsondecode(raw);
    return;
catch
end
try
    normalized = strrep(raw, '\n', newline);
    cfgStruct = jsondecode(normalized);
catch
    cfgStruct = struct();
end
end

