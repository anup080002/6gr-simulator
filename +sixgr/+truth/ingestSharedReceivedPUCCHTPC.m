function state=ingestSharedReceivedPUCCHTPC(state,item,assignment,receipt,allowed)
% Called only by the original shared PDCCH receive completion, once.
cfg=item.Context.Prepared.ReceiverConfig;
mode=string(sixgr.util.structGet(cfg,'validation.pucch_resources.power_control.closed_loop_mode','configured'));
if mode=="configured" || ~allowed || item.Context.Direction~="DL", return; end
assert(mode=="received_dci",'sixgr:truth:PUCCHPowerPolicy','Unknown power mode.');
[~,~,~,~,observation]=sixgr.truth.sharedObservationEvidence(item.Planes,item.Context.Prepared);
assert(isstruct(receipt)&&isscalar(receipt)&&isfield(receipt,'OriginalTimingEvidence') && ...
    receipt.ObservationID==string(item.ID) && ...
    receipt.OriginalTimingEvidence.ObservationSHA256==observation.sampleHash() && ...
    receipt.AvailableAtSample==observation.EndSampleExclusive && ...
    receipt.TimingDigest==string(sixgr.util.sha256Hex(char(jsonencode(receipt.OriginalTimingEvidence)))) && ...
    receipt.AvailableAtSample<=state.SharedWaveformStream.Events.NextSampleIndex && ...
    receipt.ClockEpoch==state.SharedWaveformStream.Physical.ConfigurationEpoch, ...
    'sixgr:truth:PUCCHOriginalControlReceipt','Original completed shared capture and clock must authenticate TPC.');
owners=state.SharedReceivedPUCCHPowerOwners;
assert(numel(owners)>=item.UE && isa(owners{item.UE},'sixgr.link.ReceivedPUCCHPowerControlState'), ...
    'sixgr:truth:PUCCHPowerOwnerMissing','No retroactive owner installation at receive completion.');
original=receipt; receipt=rmfield(receipt,'OriginalTimingEvidence');
[owners{item.UE},command]=owners{item.UE}.ingestReceivedDCI(cfg,assignment,receipt);
history=sixgr.util.structGet(state,'SharedReceivedPUCCHTPCReceipts',{});
history{end+1}=struct('UEIndex',item.UE,'Command',command,'OriginalClock',original, ...
    'ReceivedAssignment',assignment,'Source',"original_shared_PDCCH_received_completion");
state.SharedReceivedPUCCHPowerOwners=owners;
state.SharedReceivedPUCCHTPCReceipts=history;
end
