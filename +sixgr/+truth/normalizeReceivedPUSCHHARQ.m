function observed=normalizeReceivedPUSCHHARQ(rx,context)
% Normalize actual receiver output, independently of TX/scoring and TB CRC.
% This is not capture or scheduling proof. The coordinator must additionally
% bind the context to its physical ledger and completed observation window.
assert(isstruct(rx) && isscalar(rx) && ...
    isa(context,'sixgr.phy.ul.pusch.PUSCHUCIReceiveContext') && isscalar(context), ...
    'sixgr:truth:MissingIndependentPUSCHHARQContext', ...
    'Use the actual receiver output and its independent UCI context.');
bits=sixgr.util.structGet(rx,'DecodedHARQACKBits',int8([]));
assert((isnumeric(bits)||islogical(bits)) && isreal(bits) && ...
    (isvector(bits)||isempty(bits)) && all(isfinite(bits(:))) && ...
    all(bits(:)==0|bits(:)==1), ...
    'sixgr:truth:InvalidReceivedHARQBit','Validate received bits before integer conversion.');
e=sixgr.util.structGet(rx,'UCIReceiverEvidence',struct());
assert(isstruct(e) && isscalar(e),'sixgr:truth:InvalidPUSCHUCIReceiverEvidence', ...
    'Retain structured receiver-owned UCI evidence.');
attempted=~isempty(fieldnames(e));
count=context.Data.HARQACKBitCount;
if attempted
    assert(isfield(e,'ReceiverContextDigest') && ...
        isequal(string(e.ReceiverContextDigest),context.Digest) && ...
        isfield(e,'HARQACK') && isfield(rx,'DecodedHARQACKBits'), ...
        'sixgr:truth:PUSCHHARQReceiveContextMismatch', ...
        'The actual demultiplexer output must belong to this independent receive context.');
    usable=sixgr.truth.puschUCIFieldUsable(e.HARQACK,bits,count);
    source="actual_nrUCIDecode_field_evidence";
else
    assert(isequal(sixgr.util.structGet(rx,'NoiseVarStrictFailure',[]),true) && ...
        isequal(sixgr.util.structGet(rx,'DecodeAttempted',[]),false) && ...
        isequal(sixgr.util.structGet(rx,'ULSCHDecodeAttempted',[]),false) && ...
        isequal(sixgr.util.structGet(rx,'ReceiverUsable',[]),false) && isempty(bits), ...
        'sixgr:truth:MissingIndependentPUSCHHARQEvidence', ...
        'Only the explicitly unattempted strict-noise failure may lack decoder evidence.');
    usable=false;
    source="actual_receiver_strict_noise_gate_before_demapping";
end
observed=struct('ReceiverContextDigest',context.Digest, ...
    'HARQMappingDigest',context.Data.HARQMappingDigest, ...
    'InformationBitCount',count,'DecodedBits',int8(bits(:)), ...
    'DecodeAttempted',logical(attempted),'DecodeOk',logical(usable), ...
    'DTXFlag',logical(count>0 && ~usable),'Source',source);
end
