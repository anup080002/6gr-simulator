function complete=validateTXSpatialPowerIntervals(T,intervals,chain)
% Matrix, clock, phase orientation and exact-byte integrity are independent
% of radiated-power qualification. A matching diagonal cannot prove a beam.
complete=false; if isempty(T), return; end
prototype=sixgr.truth.rfTXSpatialPowerInterval();
assert(istable(T)&&all(ismember(prototype.Properties.VariableNames,T.Properties.VariableNames)), ...
    'sixgr:truth:TXSpatialPowerScope','Missing spatial-power columns.');
keys=T.EndpointID+"|"+string(T.StartSample);
assert(numel(unique(keys))==height(T),'sixgr:truth:TXSpatialPowerScope','Duplicate TX power intervals.');
for k=1:height(T)
    row=T(k,:); n=row.PhysicalChainCount;
    base=intervals(intervals.Role=="TX" & intervals.EndpointID==row.EndpointID & intervals.StartSample==row.StartSample,:);
    p=chain(chain.Role=="TX" & chain.EndpointID==row.EndpointID & chain.StartSample==row.StartSample,:);
    assert(height(base)==1&&height(p)==1&&row.Role=="TX" && row.Direction==base.Direction && ...
        row.EndSampleExclusive==base.EndSampleExclusive && row.SampleCount==base.SampleCount && ...
        row.SampleRateHz==base.SampleRateHz&&n==base.PhysicalPortCount && ...
        row.WaveformAmplitudeUnit==p.WaveformAmplitudeUnit && ...
        row.TXWaveformSHA256==base.OutputWaveformSHA256, ...
        'sixgr:truth:TXSpatialPowerScope','Spatial power must match the exact TX clock, layout, units and output hash.');
    assert(row.Definition=="mean_x_column_times_x_column_H_no_mean_subtraction" && ...
        row.ReferencePlane=="actual_TX_RF_output_before_antenna_channel" && ...
        row.Population=="all_samples_including_cp_and_idle" && ...
        row.Source=="actual_composite_physical_chain_TX_RF_output_samples" && ~row.RadiatedPowerQualified, ...
        'sixgr:truth:TXSpatialPowerScope','A TX second moment is not by itself EIRP/TRP or radiated qualification.');
    r=sixgr.runtime.RawCSVArrayCodec.decode(row.SecondMomentArray);
    assert(isa(r,'double')&&isequal(size(r),[n n])&&all(isfinite(r),'all') && ...
        sixgr.phy.waveform.WaveformHash.runtimeArray(r)==row.MatrixSHA256, ...
        'sixgr:truth:TXSpatialPowerHash','Second-moment bytes or dimensions changed.');
    total=row.TotalMeanSquare;
    assert(isfinite(total)&&isreal(total)&&total>=0,'sixgr:truth:TXSpatialPowerClosure','Invalid total power.');
    tolerance=max(1e-11*total,128*n*eps(total));
    diagonal=double(jsondecode(char(p.OutputPerChainMeanSquareJSON))); diagonal=diagonal(:);
    assert(norm(r-r','fro')<=tolerance && abs(imag(trace(r)))<=tolerance && ...
        abs(real(trace(r))-total)<=tolerance && ...
        max(abs(diag(r)-diagonal))<=tolerance && ...
        min(real(eig((r+r')/2)))>=-tolerance && ...
        abs(total-p.OutputTotalMeanSquare)<=tolerance, ...
        'sixgr:truth:TXSpatialPowerClosure','Measured matrix must be Hermitian PSD and close to the actual per-chain powers.');
end
complete=height(T)==nnz(intervals.Role=="TX");
end
