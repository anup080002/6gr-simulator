function h=buildConfiguredPUCCHCSIReception(state,cfg,ue,slot,observationID)
% Receiver-owned CSI/SR allocation for an independently verified no-HARQ slot.
% This does not infer no HARQ from missing UE events or pending-report rows.
assert(isempty(sixgr.truth.scheduledHARQExpectationsForOccasion(state,ue,slot)), ...
    'sixgr:truth:CombinedHARQCSIReceptionRequired', ...
    'An actual scheduled HARQ obligation cannot be erased by selecting CSI-only reception.');
id=cfg.phy.frame.DefaultIdentity; cellID=state.CurrentServingIdx(ue);
identity=struct('UEID',ue,'RNTI',state.MultiUser.RNTIStart+ue-1, ...
    'ServingCell',cellID,'PUCCHCell',cellID,'ComponentCarrier',id.ScheduledCCID, ...
    'ActiveULBWP',id.ULBWPID);
calendar=sixgr.truth.configuredCSIReportCalendar(cfg,identity,slot);
[eligible,referenceEvidence]=sixgr.truth.resolveCSIReceiveReferenceEvidence(state,cfg,ue,cellID,calendar,slot);
assert(height(calendar)==1 && calendar.ULResourceAvailable && ...
    eligible && ...
    isfinite(calendar.CSIReferenceSlot) && calendar.CSIReferenceSlot>= ...
    sixgr.util.structGet(state,'SweepPointStartSlot',1), ...
    'sixgr:truth:MissingConfiguredCSIReceiveOccasion', ...
    'CSI reception needs a legal installed occasion and causal reference resource.');
rrc=sixgr.phy.pucch.PUCCHConfigBuilder.receiverConfiguration(cfg,identity);
resource=rrc.resourceByID(calendar.PUCCHResourceID);
assert(resource.Format>=2,'sixgr:truth:InvalidCSIReceiveResource','CSI requires long-format PUCCH.');
report=sixgr.phy.mimo.CSIReportConfiguration( ...
    cfg.phy.csi.reportConfiguration,cfg.phy.csi.reportConfigurationEpoch);
srBits=0; overlap=struct();
% A resource inventory is not an installed SR procedure. Use the same
% installation boundary as the transmitter planner; the calendar itself
% still rejects malformed installed identities, periods and resource links.
if ~isempty(rrc.Data.SchedulingRequestResources)
    sr=sixgr.truth.buildConfiguredSRCalendar(cfg,identity,slot,slot);
    overlap=sixgr.truth.resolveConfiguredSROverlap(sr,slot, ...
        [resource.Data.StartSymbol resource.Data.NumSymbols],0);
    srBits=overlap.EncodedBitCount;
end
context=sixgr.truth.buildConfiguredPUCCHReceiveContext(struct( ...
    'ObservationID',string(observationID),'ConfigurationEpoch',rrc.ConfigurationEpoch, ...
    'HARQBitCount',0,'SRBitCount',srBits,'PriorityIndex',0, ...
    'CSIReportConfigID',report.ReportConfigID,'CSIConfigurationEpoch',report.Epoch),report);
assignment=sixgr.phy.pucch.PUCCHReceptionAssignment(struct( ...
    'ObservationID',string(observationID),'ResourceID',resource.ID,'RNTI',identity.RNTI, ...
    'AbsoluteSlot0',slot-1,'Source','installed_CSI_SR_calendar_verified_empty_DL_schedule', ...
    'TimingSource','received_PUCCH_DMRS','ResourceSelectionProcedure','configured_csi'),rrc,context);
enabled=sixgr.util.structGet(cfg,'phy.pucch.uciOnPUSCHEnabled',[]);
assert((isnumeric(enabled)||islogical(enabled)) && isscalar(enabled) && ...
    isreal(enabled) && isfinite(enabled) && any(enabled==[0 1]), ...
    'sixgr:truth:InvalidPUCCHTransportConfiguration','Explicit UCI transport enablement is required.');
commands={}; transport=struct();
if enabled
    [commands,transport]=sixgr.truth.findScheduledPUSCHOverlap( ...
        state,cfg,ue,slot,[resource.Data.StartSymbol resource.Data.NumSymbols]);
end
h=struct('SelectedTransport',"PUCCH",'Mapping',struct([]), ...
    'UEIndex',ue,'RNTI',identity.RNTI,'TargetSlot',slot,'ServingCell',cellID, ...
    'Assignment',assignment,'Context',context,'CSIReportCalendar',calendar, ...
    'CSIReferenceTransmissionEvidence',referenceEvidence, ...
    'CSIReportConfiguration',report,'SROverlap',overlap,'TransportScheduleEvidence',transport, ...
    'Source',"installed_CSI_SR_calendar_and_actual_gNB_schedule_not_UE_producer");
if ~isempty(commands)
    assert(isscalar(commands),'sixgr:truth:AmbiguousScheduledUCITransport', ...
        'Multiple scheduled overlapping PUSCHs need an explicit receiver selection.');
    h.SelectedTransport="PUSCH"; h.ScheduledULControl=commands{1};
    [csi,puschReport,puschCalendar]=sixgr.truth.resolveSharedPUSCHCSIReceiveObligation(state,cfg,commands{1}.Binding.Grant);
    [h.PUSCHSelectionContext,h.PUSCHMapping]=sixgr.truth.buildSharedPUSCHUCIReceiveContext( ...
        state,cfg,commands{1}.Binding.Grant,string(observationID),csi,puschReport);
    assert(~isempty(puschReport) && isempty(h.PUSCHMapping) && height(puschCalendar)==1 && ...
        puschCalendar.ObligationID==calendar.ObligationID && ...
        puschReport.ReportConfigID==report.ReportConfigID && puschReport.Epoch==report.Epoch, ...
        'sixgr:truth:CSITransportObligationMismatch','Scheduled PUSCH must retain the same CSI-only obligation.');
end
end
