function view=buildCapturedChannelDiagnosticView(parts,timeParts,maxTimeSamples,maxCoefficientRows)
% Bounded visualization of retained coefficients, not a channel execution.
% Full coefficients remain in the channel MAT archive. Doppler retains the
% entire rx1/tx1 time series; never FFT a decimated visualization sequence.
arguments
    parts cell
    timeParts cell
    maxTimeSamples (1,1) double {mustBeInteger,mustBePositive} = 128
    maxCoefficientRows (1,1) double {mustBeInteger,mustBePositive} = 32768
end
assert(numel(parts)==numel(timeParts) && ~isempty(parts), ...
    'sixgr:truth:InvalidChannelDiagnosticSegments');
[digest,hashEvidence]=sixgr.phy.waveform.concatenatedRuntimeArrayHash(parts);
shape=hashEvidence.Dimensions; shape(end+1:4)=1;
times=vertcat(timeParts{:}); times=double(times(:));
assert(shape(1)>0 && numel(times)==shape(1) && all(isfinite(times)) && ...
    all(diff(times)>0) && all(cellfun(@(p,t)size(p,1)==numel(t),parts,timeParts)), ...
    'sixgr:truth:InvalidChannelDiagnosticClock');
spatialCount=prod(shape(2:end));
% Always retain first and last sample, even for unusually large arrays.
count=min(shape(1),min(maxTimeSamples,max(2,floor(maxCoefficientRows/spatialCount))));
keep=unique(round(linspace(1,shape(1),count))).';
preview=zeros([numel(keep) shape(2:end)],'like',parts{1});
pair=zeros(shape(1),shape(2),'like',parts{1});
offset=0;
for k=1:numel(parts)
    n=size(parts{k},1);
    select=keep>offset & keep<=offset+n;
    preview(select,:,:,:)=parts{k}(keep(select)-offset,:,:,:);
    pair(offset+(1:n),:)=reshape(parts{k}(:,:,1,1),n,shape(2));
    offset=offset+n;
end
view=struct('RuntimeChannelPathGains',preview, ...
    'RuntimeChannelPathGainSampleTimes_s',times(keep), ...
    'RuntimeChannelPathGainTimeIndices0Based',keep-1, ...
    'RuntimeChannelDopplerPathGains',pair, ...
    'RuntimeChannelDopplerSampleTimes_s',times, ...
    'RuntimeChannelPathGainsSHA256',digest, ...
    'RuntimeChannelPathGainElementCount',hashEvidence.ElementCount, ...
    'RuntimeChannelPathGainDimensions',hashEvidence.Dimensions, ...
    'RuntimeChannelDiagnosticHashEvidence',hashEvidence, ...
    'RuntimeChannelDiagnosticMaxTimeSamples',maxTimeSamples, ...
    'RuntimeChannelDiagnosticRepresentation', ...
    "bounded_exact_time_samples_all_ports_full_coefficients_in_MAT_full_rate_rx1_tx1_Doppler");
end
