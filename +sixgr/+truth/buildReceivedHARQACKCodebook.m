function book=buildReceivedHARQACKCodebook(state,cfg,ue,targetSlot,receivedUL)
% UE codebook from received events available on the actual shared clock.
% No gNB scheduling ledger or expected feedback row is consulted.
if nargin<5, receivedUL=[]; end
validateattributes(ue,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(targetSlot,{'numeric'},{'scalar','real','finite','integer','positive'});
owner=state.SharedWaveformStream;
assert(isa(owner,'sixgr.truth.CoupledWaveformStream'), ...
    'sixgr:truth:HARQCodebookSharedClockRequired','A real shared owner is required.');
context=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,'1_1');
epoch=double(context.Data.ConfigurationEpoch);
ledger=sixgr.util.structGet(state,'SharedUEHARQACKEvents',{});
events=struct([]);
for k=1:numel(ledger)
    record=ledger{k};
    assert(isstruct(record) && isscalar(record) && ...
        isfield(record,'Event') && isa(record.Event,'sixgr.phy.pucch.HARQACKEvent'), ...
        'sixgr:truth:InvalidReceivedHARQLedger','Retain typed UE events.');
    e=record.Event.Data;
    if e.UEId~=ue || e.TargetSlot~=targetSlot, continue; end
    assert(record.Source=="received_dci_and_ue_harq_transition_at_shared_completion" && ...
        ~record.FeedbackTransmissionQualified && ~e.FeedbackTransmissionQualified && ...
        record.SampleRateHz==owner.SampleRateHz && ...
        record.ControlAvailableAtSample<=record.AvailableAtSample && ...
        record.AvailableAtSample<=owner.Events.NextSampleIndex, ...
        'sixgr:truth:FutureHARQFeedbackAtUCIEncoding', ...
        'The received decision must be available on this physical clock before encoding.');
    assert(e.ReceivedContextDigest==context.Digest && e.ConfigurationEpoch==epoch && ...
        e.RNTI==context.Data.RNTIValue && e.TargetSlot==e.HARQFeedbackAbsoluteSlot+1, ...
        'sixgr:truth:ReceivedHARQCodebookContextMismatch', ...
        'Do not combine events from another installed UE context, epoch or feedback slot.');
    if isempty(events), events=e; else, events(end+1)=e; end %#ok<AGROW>
end
if isempty(receivedUL)
    book=sixgr.phy.pucch.HARQACKCodebookBuilder.build('TYPE2_DYNAMIC',events,epoch);
else
    assert(receivedUL.DataAbsoluteSlot+1==targetSlot, ...
        'sixgr:truth:ReceivedHARQCodebookContextMismatch','UL grant and feedback slot differ.');
    book=sixgr.phy.pucch.HARQACKCodebookBuilder.buildForPUSCH(cfg,receivedUL,events);
end
end
