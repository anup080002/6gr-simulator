function evidence=prachNativeSampleIntervals(T,carrier)
% Exact occupied native PRACH CP/useful intervals, not carrier-symbol slots.
% Carrier PRB intersections are a resource-load model operand, not PRACH RE
% counts, measured spectrum, receiver-on intervals, or RF filter tails.
evidence=struct('ExecutedSampleIntervalsJSON',"",'ExecutedSampleIntervalSource',"", ...
    'ResourceGridPRBCount',NaN,'NativeAllocationID',"",'NativeGridSHA256',"", ...
    'NativeWaveformSHA256',"",'NativeWaveformHashPlane',"");
if nargin==0 || isempty(T), return; end
required={'channel','grid_domain','evidence_scope','active_flag','allocation_id', ...
    'native_symbol_index','native_subcarrier_start','native_subcarrier_count', ...
    'grid_subcarrier_spacing_hz','grid_subcarrier_count','grid_symbol_count', ...
    'sample_rate_hz','cp_start_sample_relative','useful_start_sample_relative', ...
    'useful_end_sample_exclusive_relative','waveform_start_sample', ...
    'frequency_first_hz','frequency_last_hz','native_grid_complete', ...
    'native_grid_sha256','waveform_sha256','waveform_hash_plane'};
assert(istable(T) && all(ismember(required,T.Properties.VariableNames)) && ...
    all(string(T.channel)=="PRACH") && all(string(T.grid_domain)=="prach_native_ofdm") && ...
    all(string(T.evidence_scope)=="runtime_observed_tx_occupancy") && ...
    all(T.active_flag==1) && all(T.native_grid_complete==1), ...
    'sixgr:truth:PRACHIntervalAuthority','Require executed native PRACH grid evidence.');
assert(all(isfinite(T.waveform_start_sample) & T.waveform_start_sample>=0 & ...
    T.waveform_start_sample==fix(T.waveform_start_sample)), ...
    'sixgr:truth:PRACHIntervalClock','Absolute transmit origin was not recorded on the native sample clock.');
for name=["allocation_id","native_grid_sha256","waveform_sha256","waveform_hash_plane", ...
        "sample_rate_hz","waveform_start_sample","grid_subcarrier_spacing_hz", ...
        "grid_subcarrier_count","grid_symbol_count"]
    assert(numel(unique(T.(name)))==1,'sixgr:truth:PRACHIntervalIdentity', ...
        'One native transmission must have one %s.',name);
end
for name=["native_grid_sha256","waveform_sha256"]
    assert(~isempty(regexp(char(string(T.(name)(1))),'^[a-f0-9]{64}$','once')), ...
        'sixgr:truth:PRACHIntervalHash','Native evidence requires sample/grid hashes.');
end
fs=double(T.sample_rate_hz(1)); origin=double(T.waveform_start_sample(1));
scs=double(T.grid_subcarrier_spacing_hz(1)); K=double(T.grid_subcarrier_count(1));
coordinates=double(T{:,{'native_symbol_index','native_subcarrier_start','native_subcarrier_count', ...
    'cp_start_sample_relative','useful_start_sample_relative','useful_end_sample_exclusive_relative'}});
assert(all(isfinite([fs origin scs K])) && fs>0 && scs>0 && origin>=0 && origin==fix(origin) && ...
    all(isfinite(coordinates)&coordinates==fix(coordinates),'all') && ...
    all(coordinates(:,1)>=0 & coordinates(:,1)<T.grid_symbol_count & ...
    coordinates(:,2)>=0 & coordinates(:,3)>0 & coordinates(:,2)+coordinates(:,3)<=K & ...
    coordinates(:,4)>=0 & coordinates(:,5)>=coordinates(:,4) & ...
    coordinates(:,6)-coordinates(:,5)==fs/scs), ...
    'sixgr:truth:PRACHIntervalClock','Native CP/useful samples and FFT spacing must agree.');
first=(coordinates(:,2)-K/2)*scs;
last=(coordinates(:,2)+coordinates(:,3)-1-K/2)*scs;
assert(all(abs(first-T.frequency_first_hz)<1e-6 & abs(last-T.frequency_last_hz)<1e-6), ...
    'sixgr:truth:PRACHIntervalFrequency','Native bin coordinates disagree with frequency evidence.');
gridRB=double(carrier.NSizeGrid); carrierSCS=1000*double(carrier.SubcarrierSpacing);
assert(K*scs==12*gridRB*carrierSCS,'sixgr:truth:PRACHIntervalCarrier', ...
    'Native and carrier grid bandwidths differ.');
lower=((0:gridRB-1)*12-6*gridRB-.5)*carrierSCS;
upper=lower+12*carrierSCS;
symbols=unique(coordinates(:,1),'sorted');
rows=repmat(struct('StartSample',NaN,'EndSampleExclusive',NaN,'SampleRateHz',fs, ...
    'NativeSymbolIndex0',NaN,'CarrierPRBIntersectionSet0Based',[]),numel(symbols),1);
for k=1:numel(symbols)
    selected=coordinates(:,1)==symbols(k);
    clock=unique(coordinates(selected,4:6),'rows');
    assert(size(clock,1)==1,'sixgr:truth:PRACHIntervalClock','Ports disagree on native symbol timing.');
    occupied=false(1,gridRB);
    runs=unique([first(selected)-scs/2,last(selected)+scs/2],'rows');
    for j=1:size(runs,1)
        occupied=occupied | (upper>runs(j,1) & lower<runs(j,2));
    end
    assert(any(occupied),'sixgr:truth:PRACHIntervalFrequency','PRACH has no carrier-band intersection.');
    rows(k).StartSample=origin+clock(1);
    rows(k).EndSampleExclusive=origin+clock(3);
    rows(k).NativeSymbolIndex0=symbols(k);
    rows(k).CarrierPRBIntersectionSet0Based=find(occupied)-1;
end
assert(all([rows(2:end).StartSample]>=[rows(1:end-1).EndSampleExclusive]), ...
    'sixgr:truth:PRACHIntervalClock','Native occupied symbols overlap in time.');
evidence.ExecutedSampleIntervalsJSON=string(jsonencode(rows));
evidence.ExecutedSampleIntervalSource="executed_native_PRACH_CP_useful_samples_not_RF_activity";
evidence.ResourceGridPRBCount=gridRB;
evidence.NativeAllocationID=string(T.allocation_id(1));
evidence.NativeGridSHA256=string(T.native_grid_sha256(1));
evidence.NativeWaveformSHA256=string(T.waveform_sha256(1));
evidence.NativeWaveformHashPlane=string(T.waveform_hash_plane(1));
end
