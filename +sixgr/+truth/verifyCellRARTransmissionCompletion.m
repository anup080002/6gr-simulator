function proof=verifyCellRARTransmissionCompletion(owner,item)
% Original cell RAR component + successful shared TX execution, not UE RX.
% The aggregate TX IQ is not an isolated RAR power measurement.
id='sixgr:truth:CellRARTransmissionContract';
assert(isa(owner,'sixgr.truth.CoupledWaveformStream') && isstruct(item) && ...
    isscalar(item) && item.Kind=="CellRARTX" && item.UE==0 && numel(item.Planes)==1,id,'Require the original cell RAR TX owner/item.');
c=item.Context; p=c.Prepared; r=c.EnqueueReceipt;
registered=owner.originalCellRARTransmissionContract(item.ID);
assert(registered.ContextSHA256== ...
    sixgr.phy.waveform.WaveformHash.bytes(getByteStreamFromArray(c)) && ...
    c.ComponentID==item.ID && p.StageName=="Msg2" && p.Direction=="DL" && ...
    c.PhysicalConfigurationEpoch==owner.Physical.ConfigurationEpoch && ...
    string(item.Planes.ReceiverID)==c.TransmitterPlane && ...
    c.TransmitterPlane=="gnb_"+c.ServingCell+":tx",id,'The original prepared attempt and TX plane cannot change.');
original=owner.Events.originalEnqueueReceipt("gnb_"+c.ServingCell,c.ComponentID);
assert(isequaln(original,r) && r.StartSample==sixgr.phy.ra.preparedStageTransmitStartSample(p) && ...
    r.EndSampleExclusive==r.StartSample+p.SampleCount && r.SampleRateHz==owner.SampleRateHz && ...
    r.OriginalSampleSHA256==sixgr.phy.waveform.WaveformHash.numeric(p.PhysicalWaveform), ...
    id,'Bind original accepted component bytes, not a fabricated completion marker.');
o=item.Planes.Observation; segments=item.Planes.Segments;
assert(o.isComplete() && o.StartSample==r.StartSample && o.EndSampleExclusive==r.EndSampleExclusive && ...
    o.EndSampleExclusive<=r.EndSampleExclusive && o.SampleRateHz==r.SampleRateHz && ...
    owner.Events.NextSampleIndex==r.EndSampleExclusive && iscell(segments) && ~isempty(segments), ...
    id,'Complete the original emitted support on its exact clock.');
samples=o.readComplete(); cursor=r.StartSample; nonzero=0;
for k=1:numel(segments)
    s=segments{k}; e=s.Execution;
    found=find(cellfun(@(v)v.StartSample==s.StartSample && ...
        v.EndSampleExclusive==s.EndSampleExclusive,owner.Events.ExecutionTrace));
    assert(isscalar(found) && s.StartSample==cursor && s.EndSampleExclusive>cursor && ...
        s.EndSampleExclusive<=r.EndSampleExclusive && e.StartSample==cursor && ...
        e.EndSampleExclusive==s.EndSampleExclusive && e.SampleRateHz==r.SampleRateHz && ...
        e.ConfigurationEpoch==c.PhysicalConfigurationEpoch && ...
        string(e.Source)=="composed_tx_retained_rf_per_link_channel_sum_receiver_noise_rf" && ...
        string(e.ApproximationMode)=="none",id,'Require contiguous original shared physical execution.');
    originalExecution=owner.Events.ExecutionTrace{found}.Execution;
    assert(isequaln(e.ExecutedContributors,originalExecution.ExecutedContributors) && ...
        isequaln(e.TX,originalExecution.TX),id,'Do not replace original physical contributor or RF receipts.');
    node=e.ExecutedContributors(string({e.ExecutedContributors.TransmitterID})==r.TransmitterID);
    assert(isscalar(node) && isequal(node.Receipt.CompleteContributorList,true) && ...
        node.Receipt.Schema=="consumed_waveform_components/v1" && ...
        node.Receipt.NonzeroIntervalSchema=="exact_absolute_component_nonzero_runs/v1" && ...
        node.Receipt.StartSample==cursor && node.Receipt.EndSampleExclusive==s.EndSampleExclusive && ...
        node.CommittedThroughSample>=s.EndSampleExclusive,id,'Require the original consumed component population.');
    component=node.Receipt.Components(string({node.Receipt.Components.ComponentID})==c.ComponentID);
    rows=(cursor-r.StartSample+1):(s.EndSampleExclusive-r.StartSample);
    part=p.PhysicalWaveform(rows,:); active=any(part~=0,2); edge=diff([false;active;false]);
    runs=[find(edge==1)-1 find(edge==-1)-1]+cursor;
    assert(isscalar(component) && component.OriginalSampleSHA256==r.OriginalSampleSHA256 && ...
        component.StartSample==cursor && component.EndSampleExclusive==s.EndSampleExclusive && ...
        component.NonzeroSampleCount==nnz(part) && component.NonzeroTimeSampleCount==nnz(active) && ...
        isequal(component.NonzeroIntervals,runs),id,'The original component was cancelled, replaced or truncated.');
    tx=e.TX(string({e.TX.ID})==r.TransmitterID);
    assert(isscalar(tx) && string(tx.Replay.RFOutputWaveformSHA256)== ...
        string(sixgr.rf.waveformSHA256(samples(rows,:))),id,'Preserve actual aggregate post-TX-RF samples.');
    nonzero=nonzero+nnz(part); cursor=s.EndSampleExclusive;
end
assert(cursor==r.EndSampleExclusive && nonzero>0,id,'Silent/partial components cannot claim emitted RAR.');
proof=struct('ContractVersion',"executed_cell_RAR_component/v1", ...
    'ComponentID',string(item.ID),'ServingCell',c.ServingCell, ...
    'RARNTI',p.RARNTI,'AbsoluteSlot',p.AbsoluteSlot, ...
    'ReceiverReceiptSHA256',p.ReceiverReceiptSHA256,'CellCalendarSHA256',p.CellCalendarSHA256, ...
    'RARPlanSHA256',p.RARPlan.PlanSHA256,'RARPayloadSHA256',sixgr.protocol.ProtocolHash.bytes(p.Tx.RAR.Bytes), ...
    'ContextSHA256',registered.ContextSHA256,'EnqueueReceiptSHA256',r.ReceiptSHA256, ...
    'OriginalSampleSHA256',r.OriginalSampleSHA256,'TransmitObservationSHA256',o.sampleHash(), ...
    'TransmitStartSample',r.StartSample,'TransmitEndSampleExclusive',r.EndSampleExclusive, ...
    'SampleRateHz',r.SampleRateHz,'PhysicalConfigurationEpoch',c.PhysicalConfigurationEpoch, ...
    'CompletedAtSample',owner.Events.NextSampleIndex, ...
    'PhysicalTransmissionVerified',true,'ReceiverExecutionClaimed',false, ...
    'ObservationScope',"aggregate_post_TX_RF_original_RAR_contributor_not_isolated_power");
end
