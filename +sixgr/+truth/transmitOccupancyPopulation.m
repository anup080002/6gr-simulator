function population=transmitOccupancyPopulation(state,cfg)
% Freeze supplied lifecycle identity at the actual first-active-sample event.
% Never substitute RX-callback point, row order, or a manufactured run ID.
owner=state.SharedWaveformStream;
population=struct('RunFolder',string(sixgr.util.structGet(state,'RunFolder',"")), ...
    'RunID',string(sixgr.util.structGet(cfg,'run.runTag',"")), ...
    'ExecutionID',string(sixgr.util.structGet(cfg,'run.executionID',"")), ...
    'ConfigHash',string(sixgr.util.structGet(cfg,'meta.configHash',"")), ...
    'ScenarioID',string(sixgr.util.structGet(cfg,'run.scenarioID',"")), ...
    'RandomSeed',double(sixgr.util.structGet(cfg,'run.seed',NaN)), ...
    'ChannelSeed',double(sixgr.util.structGet(cfg,'channel.seed',NaN)), ...
    'SweepPointIndex',double(sixgr.util.structGet(state,'CurrentSweepPointIndex',NaN)), ...
    'ConfiguredSNR_dB',double(sixgr.util.structGet(state,'CurrentSNR_dB',NaN)), ...
    'BoundAtSample',double(owner.Events.NextSampleIndex), ...
    'Source',"actual_first_active_sample_commit_runtime_context");
% Missing lifecycle fields remain visibly missing; they cannot qualify a join.
end
