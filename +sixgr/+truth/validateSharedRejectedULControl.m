function grant=validateSharedRejectedULControl(state,control)
% A missing UL command is a completed receiver outcome, not a crash or flag.
owner=state.SharedWaveformStream;
assert(isa(owner,'sixgr.truth.CoupledWaveformStream') && isscalar(owner) && ...
    isstruct(control) && isscalar(control) && ...
    isequal(sixgr.util.structGet(control,'Allowed',[]),false), ...
    'sixgr:truth:InvalidSharedULRejectedControl','Require one actually rejected UL control result.');
controls=sixgr.util.structGet(state,'SharedReceivedGrantControls',{});
assert(isfield(control,'Key') && ...
    sum(cellfun(@(x)isequaln(x,control),controls))==1 && ...
    sum(cellfun(@(x)isequal(x.Key,control.Key),controls))==1, ...
    'sixgr:truth:UnretainedSharedULRejectedControl','Use the exact uniquely retained receiver record.');
assert(all(isfield(control,{'ReceiverTrial','RejectedControlObservation','ReceivedAssignment','Grant','AvailableAtSample'})), ...
    'sixgr:truth:MissingSharedULRejectedControlEvidence','Retain the physical rejection and its grant identity.');
trial=control.ReceiverTrial; observation=control.RejectedControlObservation;
assert(isstruct(trial) && isscalar(trial) && ...
    isequal(sixgr.util.structGet(trial,'Crash',[]),false) && ...
    isequal(sixgr.util.structGet(trial,'DecodeAttempted',[]),true) && ...
    isequal(sixgr.util.structGet(trial,'PDCCHCausalGrantDecodeOk',[]),false), ...
    'sixgr:truth:InvalidSharedULRejectedControlEvidence', ...
    'A crash, unattempted decode or accepted DCI cannot stand for a missed UL command.');
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && observation.isComplete() && ...
    observation.SampleRateHz==owner.SampleRateHz && ...
    observation.EndSampleExclusive==control.AvailableAtSample && ...
    observation.EndSampleExclusive<=owner.Events.NextSampleIndex && ...
    isequal(sixgr.util.structGet(trial,'PDCCHObservationStartSample',[]),observation.StartSample) && ...
    isequal(sixgr.util.structGet(trial,'PDCCHObservationEndSampleExclusive',[]),observation.EndSampleExclusive), ...
    'sixgr:truth:InvalidSharedULRejectedControlClock','Bind the actual completed PDCCH receive window.');
assert(isstruct(control.ReceivedAssignment) && isscalar(control.ReceivedAssignment) && ...
    isempty(fieldnames(control.ReceivedAssignment)), ...
    'sixgr:truth:RejectedULHasReceivedAssignment','Rejected control must not install a UE allocation.');
grant=control.Grant;
sixgr.phy.grant.assertGrantTimingIdentity(grant,'UL');
assert(string(grant.Direction)=="UL" && grant.UEIndex>=1 && grant.UEIndex<=state.NumUsers && ...
    grant.RNTI==state.MultiUser.RNTIStart+grant.UEIndex-1, ...
    'sixgr:truth:PUSCHReceiveOnlyIdentityMismatch','Bind the rejected UL command to the configured UE/RNTI.');
sixgr.phy.grant.assertPHYGrantDimensions(grant.PHYGrant,'rejected_ul_control');
end
