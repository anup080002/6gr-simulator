function direction=resolvePUCCHFeedbackDirection(rows)
% Feedback source direction is distinct from the UL PUCCH transport.
if isstruct(rows), rows=struct2table(rows,'AsArray',true); end
assert(istable(rows) && height(rows)>0, ...
    'sixgr:truth:MissingPUCCHFeedbackDirection','Retain nonempty feedback rows.');
names=string(rows.Properties.VariableNames);
if ismember('FeedbackForDirection',names)
    values=upper(strtrim(string(rows.FeedbackForDirection)));
    assert(size(values,2)==1 && numel(values)==height(rows) && ...
        all(~ismissing(values) & ismember(values,["DL","UL"])), ...
        'sixgr:truth:InvalidPUCCHFeedbackDirection', ...
        'Explicit feedback direction must be a nonmissing DL/UL value per row.');
else
    % Legacy pending-feedback rows use Direction for the DL source. An UL
    % transport row without its explicit feedback field is not sufficient.
    assert(ismember('Direction',names), ...
        'sixgr:truth:MissingPUCCHFeedbackDirection','Feedback source direction is required.');
    values=upper(strtrim(string(rows.Direction)));
    assert(size(values,2)==1 && numel(values)==height(rows) && ...
        all(~ismissing(values) & values=="DL"), ...
        'sixgr:truth:MissingPUCCHFeedbackDirection', ...
        'Do not infer the feedback source from an UL transport direction.');
end
assert(numel(unique(values))==1,'sixgr:truth:MixedPUCCHFeedbackDirections', ...
    'One exported physical occasion cannot collapse conflicting source directions.');
direction=values(1);
end
