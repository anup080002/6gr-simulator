function [fields,evidence]=proveSharedSRSChannelReference(context,carrier,indices,ofdm,clock,timing,frequency)
% Post-receiver SRS LS/NMSE support is NOT the independent pre-RF power support.
% Prove exactly the desired samples selected by the executed RX delay clock.
% Recorded CFO is multiplicative and does not enlarge this sample dependency.
fields=sixgr.link.srsReferenceEvidence(); evidence=struct();
try
    id='sixgr:truth:SRSChannelReferenceSupport';
    assert(isfield(context,'SRSIsolationOwner') && isfield(context,'SRSIsolationItem') && ...
        ~isempty(fieldnames(clock)) && ...
        string(clock.TimingAlignmentSource)== ...
            "recorded_RX_endpoint_integer_delay_exact_retained_sample_selection" && ...
        clock.ReceiverTimingIncluded && ~clock.TXTimingReapplied && ~clock.GainOrPhaseFitted,id, ...
        'The legacy SRS reference needs its own actual recorded receiver-clock proof.');
    original=context.DesiredReferenceObservation;
    assert(clock.ReceiveStartSample==context.Observation.StartSample+timing.AppliedTimingCorrectionSamples && ...
        clock.ReceiveEndSampleExclusive-clock.ReceiveStartSample==timing.DemodulatedSampleCount && ...
        clock.ReferenceStartSample==clock.ReceiveStartSample-clock.RecordedReceiverTimingOffset_samples && ...
        clock.ReferenceEndSampleExclusive==clock.ReceiveEndSampleExclusive-clock.RecordedReceiverTimingOffset_samples,id, ...
        'Retain the actual noisy receiver timing and original executed RX delay separately.');
    assert(frequency.ReceiverCFOIncluded && ...
        string(frequency.FrequencySource)=="executed_RX_endpoint_not_configured_or_merged_TX_RX" && ...
        string(frequency.FrequencySampleClock)=="RX_absolute_sample_after_executed_timing_delay" && ...
        frequency.ReceiveStartSample==clock.ReceiveStartSample && ...
        frequency.ReceiveEndSampleExclusive==clock.ReceiveEndSampleExclusive && ...
        ~frequency.ReceiverEstimatorInput && ~frequency.GainOrPhaseFitted && ...
        frequency.AdditionalRFExecutions==0 && frequency.AdditionalChannelExecutions==0,id, ...
        'Retain the actual multiplicative CFO transform separately from its unchanged sample support.');
    K=12*double(carrier.NSizeGrid); L=double(carrier.SymbolsPerSlot);
    [k,l,~]=ind2sub([K,L,double(context.Prepared.Tx.SRS.NumSRSPorts)],double(indices(:)));
    selectedTiming=timing;
    selectedTiming.AppliedTimingCorrectionSamples=clock.ReferenceStartSample-original.StartSample;
    support=sixgr.phy.srs.srsAntennaPowerFFTSupport(carrier,ofdm,selectedTiming, ...
        original.StartSample,original.EndSampleExclusive,unique([k l]-1,'rows','sorted'), ...
        "recorded_practical_RX_clock_reference_native_demodulation");
    proof=sixgr.truth.sharedSRSComponentIsolation(context.SRSIsolationItem,context, ...
        context.SRSIsolationOwner,support.FFTIntervals);
    evidence=struct('ContractVersion',"sixgr.srs.isolated_RX_clock_reference/v1", ...
        'FFTSupport',support,'ClockEvidence',clock,'FrequencyEvidence',frequency, ...
        'ReferenceHashPlane',"actual_desired_link_after_recorded_RX_delay_selection_and_CFO_transform", ...
        'Isolation',proof, ...
        'ReferenceUsedByReceiver',false,'HardwareConformanceQualified',false, ...
        'AccuracyQualified',false,'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0);
    fields.ChannelNMSEReferenceAvailable=proof.Available;
    fields.ChannelNMSEReferenceStatus=string(proof.Status);
    if proof.Available
        fields.ChannelNMSEReferenceStatus="available_isolated_emitted_SRS_RX_clock_model_reference";
    end
    fields.ChannelNMSEReferenceEvidenceJSON=string(jsonencode(evidence));
    fields.ChannelNMSEReferenceEvidenceSHA256=string(sixgr.rrc.asn1.asn1SHA256Hex( ...
        unicode2native(char(fields.ChannelNMSEReferenceEvidenceJSON),'UTF-8')));
catch cause
    fields=sixgr.link.srsReferenceEvidence(); evidence=struct();
    fields.ChannelNMSEReferenceErrorIdentifier=string(cause.identifier);
    fields.ChannelNMSEReferenceStatus="unavailable_RX_clock_reference_proof_failed";
end
end
