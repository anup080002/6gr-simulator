function indices=bindScheduledPUCCHFeedbackRows(mapping,rows)
% Associate existing logical producer rows with independent gNB bit records.
% Missing-DCI schedule records need no invented UE row. ACK values are unused.
assert(isstruct(mapping) && isscalar(mapping) && isfield(mapping,'Records') && ...
    istable(rows) && all(ismember({'UEIndex','RNTI','SourceSlot','HarqID', ...
    'ScheduledAbsoluteSlot'},rows.Properties.VariableNames)), ...
    'sixgr:truth:ScheduledPUCCHProducerMismatch','Retain scheduled and logical identities.');
records=mapping.Records;
assert(isstruct(records) && all(isfield(records,{'UEIndex','RNTI','SourceSlot', ...
    'HARQProcess','TargetSlot','BitIndex'})), ...
    'sixgr:truth:ScheduledPUCCHProducerMismatch','Retain each independent scheduling key.');
keys=[[records.UEIndex].' [records.RNTI].' [records.SourceSlot].' ...
    [records.HARQProcess].' [records.TargetSlot].'];
names={'UEIndex','RNTI','SourceSlot','HarqID','ScheduledAbsoluteSlot'};
producer=zeros(height(rows),numel(names));
for k=1:numel(names)
    raw=rows.(names{k});
    assert(isnumeric(raw) && isreal(raw) && iscolumn(raw) && ...
        all(isfinite(raw)) && all(raw==fix(raw)) && all(raw>=0), ...
        'sixgr:truth:ScheduledPUCCHProducerMismatch','Producer identities must be exact numeric scalars.');
    producer(:,k)=double(raw);
end
assert(size(unique(producer,'rows'),1)==height(rows), ...
    'sixgr:truth:ScheduledPUCCHProducerMismatch','Duplicate logical producer identities are not allowed.');
indices=zeros(height(rows),1);
for k=1:height(rows)
    hit=find(all(keys==producer(k,:),2));
    assert(isscalar(hit) && records(hit).BitIndex==hit, ...
        'sixgr:truth:ScheduledPUCCHProducerMismatch','Bind each producer to exactly one ordered gNB record.');
    indices(k)=hit;
end
end
