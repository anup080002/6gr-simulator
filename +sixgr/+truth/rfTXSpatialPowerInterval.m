function T=rfTXSpatialPowerInterval(replay,base)
% One losslessly encoded second moment per actual TX interval, never from
% antenna counts, intended precoders, diagonal powers or historical labels.
row=struct('EndpointID',"",'Role',"TX",'Direction',"", ...
    'StartSample',NaN,'EndSampleExclusive',NaN,'SampleRateHz',NaN, ...
    'SampleCount',NaN,'PhysicalChainCount',NaN,'WaveformAmplitudeUnit',"undeclared", ...
    'TotalMeanSquare',NaN,'SecondMomentArray',"",'MatrixSHA256',"",'TXWaveformSHA256',"", ...
    'Definition',"mean_x_column_times_x_column_H_no_mean_subtraction", ...
    'ReferencePlane',"actual_TX_RF_output_before_antenna_channel", ...
    'Population',"all_samples_including_cp_and_idle", ...
    'Source',"actual_composite_physical_chain_TX_RF_output_samples", ...
    'RadiatedPowerQualified',false);
T=struct2table(row); T=T([],:); if nargin==0, return; end
enabled=logical(sixgr.util.structGet(replay,'TXSpatialPowerEnabled',false));
if ~enabled
    assert(~isfield(replay,'TXSpatialPower'),'sixgr:truth:TXSpatialPowerScope', ...
        'Spatial power evidence needs its producer enable declaration.');
    return;
end
assert(isscalar(enabled)&&isfield(replay,'TXSpatialPower')&&height(base)==1&&base.Role=="TX", ...
    'sixgr:truth:TXSpatialPowerMissing','An enabled TX must supply measured spatial power.');
e=replay.TXSpatialPower;
assert(isstruct(e)&&isscalar(e)&&all(isfield(e,{'Contract','SecondMoment', ...
    'SampleCount','PhysicalChainCount','TotalMeanSquare','MatrixSHA256','Definition','Plane','Population','Source'})) && ...
    e.Contract=="physical_tx_spatial_power/v1" && e.SampleCount==base.SampleCount && ...
    e.PhysicalChainCount==base.PhysicalPortCount && e.Definition==row.Definition && ...
    e.Plane==row.ReferencePlane && e.Population==row.Population && e.Source==row.Source, ...
    'sixgr:truth:TXSpatialPowerScope','Use same-execution physical TX samples and their exact interval.');
for name=["EndpointID","Role","Direction","StartSample","EndSampleExclusive","SampleRateHz","SampleCount"]
    row.(name)=base.(name);
end
row.PhysicalChainCount=e.PhysicalChainCount;
row.TotalMeanSquare=e.TotalMeanSquare;
row.SecondMomentArray=sixgr.runtime.RawCSVArrayCodec.encode(e.SecondMoment);
row.MatrixSHA256=string(e.MatrixSHA256); row.TXWaveformSHA256=base.OutputWaveformSHA256;
row.WaveformAmplitudeUnit=string(sixgr.util.structGet(replay,'WaveformAmplitudeUnit','undeclared'));
T=struct2table(row);
end
