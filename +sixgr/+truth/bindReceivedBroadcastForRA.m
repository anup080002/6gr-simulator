function [cfg, recovery, firstRuntimeSlot] = bindReceivedBroadcastForRA(cfg, received)
% Bind received broadcast identity and its completion clock, never a TX hint.
% The returned runtime slot is one based; sample extents are absolute and
% end-exclusive. RAConfig still selects the next legal PRACH occasion.
required = {'Ok','SSBIdentityVerified','SSBIndex','ObservedSSBOccasionIndex', ...
    'PBCHHypothesisSSBIndex','SSBIndexSource','SIB1', ...
    'ObservationEndSampleExclusive','ObservationSampleRateHz'};
assert(isstruct(received) && isscalar(received) && all(isfield(received,required)), ...
    'sixgr:truth:MissingReceivedBroadcast','RA requires completed receiver-owned broadcast evidence.');
assert(isequal(received.Ok,true) && isequal(received.SSBIdentityVerified,true), ...
    'sixgr:truth:UnsuccessfulReceivedBroadcast','Undecoded broadcast cannot establish an RA association.');
index=double(received.SSBIndex);
assert(isscalar(index) && isfinite(index) && index>=0 && index==fix(index) && ...
    isequal(index,double(received.ObservedSSBOccasionIndex)) && ...
    isequal(index,double(received.PBCHHypothesisSSBIndex)), ...
    'sixgr:truth:ReceivedBroadcastIdentityMismatch','Observed and decoded SSB identities must agree.');
source=string(received.SSBIndexSource);
assert(isscalar(source) && ~ismissing(source) && strlength(strtrim(source))>0, ...
    'sixgr:truth:MissingReceivedBroadcast','Retain the receiver identity source.');
recovery=received.SIB1;
flags={'MIBDecoded','BCHCrcPass','DCICrcPass','DLSCHCrcPass','SIB1ASN1DecodeOk','SIB1SemanticValid'};
assert(isstruct(recovery) && isscalar(recovery) && all(isfield(recovery,flags)), ...
    'sixgr:truth:MissingReceivedBroadcast','RA requires the decoded MIB and SIB1 receipt.');
for k=1:numel(flags)
    assert(isequal(recovery.(flags{k}),true), ...
        'sixgr:truth:UnsuccessfulReceivedBroadcast','Broadcast stage %s did not decode.',flags{k});
end
fs=double(received.ObservationSampleRateHz);
last=double(received.ObservationEndSampleExclusive);
samplesPerSlot=fs*sixgr.time.slotDurationSec(cfg);
assert(isscalar(fs) && isfinite(fs) && fs>0 && isscalar(last) && ...
    isfinite(last) && last>0 && last==fix(last) && last<flintmax && ...
    isfinite(samplesPerSlot) && samplesPerSlot>0 && samplesPerSlot==fix(samplesPerSlot), ...
    'sixgr:truth:ReceivedBroadcastClockMismatch','Broadcast completion must have an exact sample/slot clock.');
firstRuntimeSlot=ceil(last/samplesPerSlot)+1;
cfg=sixgr.util.structSet(cfg,'phy.ssb.runtimeSSBIndex',index);
cfg=sixgr.util.structSet(cfg,'random_access.associated_ssb_index',index);
cfg=sixgr.util.structSet(cfg,'random_access.associated_ssb_selection_source',char(source));
end
