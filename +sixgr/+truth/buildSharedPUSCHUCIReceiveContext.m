function [context,mapping]=buildSharedPUSCHUCIReceiveContext(state,cfg,grant,observationID,csiObligation,csiConfig)
% Build the gNB schema from the complete actual DL schedule, never UE bits.
% Caller must prove the UL receive window and independent CSI occasion.
% This constructor neither authorizes a UE transmission nor commits feedback.
if nargin<6, csiConfig=[]; end
validateattributes(grant.UEIndex,{'numeric'},{'scalar','real','finite','integer','positive'});
assert(grant.UEIndex<=state.NumUsers && ...
    grant.RNTI==state.MultiUser.RNTIStart+grant.UEIndex-1, ...
    'sixgr:truth:HARQMappingUEIdentityMismatch','Bind this grant to the configured shared UE/RNTI.');
sixgr.phy.grant.assertGrantTimingIdentity(grant,'UL');
sixgr.phy.pdcch.ConnectedDCIProfile.validatePolicy( ...
    sixgr.util.structGet(cfg,'phy.pdcch.operatorControl.connected_dci',struct()));
installed=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,'0_1');
packed=sixgr.phy.pdcch.DCIContext(grant.DCI.ContextData);
assert(packed.Digest==installed.Digest && grant.RNTI==installed.Data.RNTIValue && ...
    installed.Data.DAIWidth==2 && isfield(grant,'ULTotalDAIAuthority'), ...
    'sixgr:truth:MissingScheduledPUSCHHARQAuthority','Use this installed ordinary connected UL grant.');
target=grant.TimingDecision.DataAbsoluteSlot+1;
expectations=sixgr.truth.scheduledHARQExpectationsForOccasion(state,grant.UEIndex,target);
if ~isempty(expectations)
    base=sixgr.truth.buildScheduledHARQACKMapping(state,cfg,grant.UEIndex,target);
    mapping=sixgr.truth.bindScheduledPUSCHHARQMapping(base,cfg,grant);
    context=sixgr.truth.buildScheduledPUSCHUCIReceiveContext( ...
        mapping,observationID,csiObligation,csiConfig);
    return;
end
% Do not call the positive-HARQ mapper with a fabricated DL record. Rebuild
% the UL scheduling authority from an empty gNB assignment set, not from UE
% reception. Raw DAI=3 alone is insufficient: it also represents 4,8,... DLs.
rebuilt=sixgr.truth.prepareScheduledULDAI(struct(),cfg,grant);
assert(isequaln(rebuilt.ULTotalDAIAuthority,grant.ULTotalDAIAuthority) && ...
    isequal(rebuilt.DCI.Bits,grant.DCI.Bits), ...
    'sixgr:truth:NonemptyScheduledPUSCHHARQAuthority', ...
    'Zero physical HARQ assignments require the exact independently empty UL DAI authority.');
names=["ReportConfigID","ConfigurationEpoch"];
assert(isstruct(csiObligation) && isscalar(csiObligation) && ...
    all(isfield(csiObligation,names)) && ...
    isempty(setdiff(string(fieldnames(csiObligation)),names)), ...
    'sixgr:truth:InvalidScheduledPUSCHCSIObligation', ...
    'Use only the installed CSI identity and epoch, not a UE report or length.');
scheduled=sixgr.phy.pdcch.decodeDCIPayload(grant.DCI.Bits,'0_1',packed);
assert(scheduled.Fields.first_dai==3,'sixgr:truth:NonemptyScheduledPUSCHHARQAuthority', ...
    'An empty ordinary Type-2 UL DAI authority must carry the on-wire value 11.');
assignment=struct('GrantContextID',string(grant.PHYGrant.GrantContextId), ...
    'ScheduledULPayloadHash',string(scheduled.PayloadHash));
assert(strlength(assignment.GrantContextID)>0 && strlength(assignment.ScheduledULPayloadHash)>0, ...
    'sixgr:truth:MissingScheduledPUSCHHARQAuthority','Retain the UL grant and scheduled payload identity.');
context=sixgr.phy.ul.pusch.PUSCHUCIReceiveContext(struct( ...
    'ObservationID',observationID,'ConfigurationEpoch',installed.Data.ConfigurationEpoch, ...
    'AssignmentDigest',sixgr.phy.pucch.PUCCHUtil.hash(assignment), ...
    'HARQMappingDigest',"",'HARQACKBitCount',0,'ConfiguredGrantUCIBitCount',0, ...
    'CSIReportConfigID',csiObligation.ReportConfigID, ...
    'CSIConfigurationEpoch',csiObligation.ConfigurationEpoch));
context.bitBudget(csiConfig);
mapping=struct([]); % No fake grant/HARQ/TBS row for an empty obligation.
end
