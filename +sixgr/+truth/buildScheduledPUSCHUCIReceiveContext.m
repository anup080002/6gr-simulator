function context=buildScheduledPUSCHUCIReceiveContext(mapping,observationID,csiObligation,csiConfig)
% Ordinary connected PUSCH: gNB mapping -> payload-free receive schema.
% Caller proves the physical UL observation and configured CSI occasion.
% This path has no configured-grant UCI; it must not be used for CG grants.
if nargin<4, csiConfig=[]; end
probe=struct('MappingDigest',mapping.Digest,'UEIndex',mapping.UEIndex, ...
    'RNTI',mapping.RNTI,'TargetSlot',mapping.TargetSlot,'DecodedBits',int8([]), ...
    'DecodeOk',false,'DTXFlag',true,'Transport',"PUSCH");
sixgr.truth.mapScheduledPUSCHHARQFeedback(mapping,probe);
assert(all(isfield(mapping,{'ULGrantContextID','ULScheduledPayloadHash'})), ...
    'sixgr:truth:MissingScheduledPUSCHHARQAuthority','Retain the scheduled UL grant and DCI identities.');
for name=["ULGrantContextID","ULScheduledPayloadHash"]
    value=mapping.(name);
    assert(((isstring(value) && isscalar(value)) || (ischar(value) && isrow(value))) && ...
        ~ismissing(string(value)) && strlength(strtrim(string(value)))>0, ...
        'sixgr:truth:MissingScheduledPUSCHHARQAuthority','Scheduled UL identities must be nonempty scalar text.');
end
names=["ReportConfigID","ConfigurationEpoch"];
assert(isstruct(csiObligation) && isscalar(csiObligation) && all(isfield(csiObligation,names)) && ...
    isempty(setdiff(string(fieldnames(csiObligation)),names)), ...
    'sixgr:truth:InvalidScheduledPUSCHCSIObligation', ...
    'Use only the installed CSI report identity and epoch, not a UE report or its length.');
assignment=struct('GrantContextID',mapping.ULGrantContextID, ...
    'ScheduledULPayloadHash',mapping.ULScheduledPayloadHash);
context=sixgr.phy.ul.pusch.PUSCHUCIReceiveContext(struct( ...
    'ObservationID',observationID,'ConfigurationEpoch',mapping.ConfigurationEpoch, ...
    'AssignmentDigest',sixgr.phy.pucch.PUCCHUtil.hash(assignment), ...
    'HARQMappingDigest',mapping.Digest,'HARQACKBitCount',mapping.BitCount, ...
    'ConfiguredGrantUCIBitCount',0,'CSIReportConfigID',csiObligation.ReportConfigID, ...
    'CSIConfigurationEpoch',csiObligation.ConfigurationEpoch));
context.bitBudget(csiConfig); % Reject unavailable, stale or wrong-transport CSI now.
end
