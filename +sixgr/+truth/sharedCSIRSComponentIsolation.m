function evidence=sharedCSIRSComponentIsolation(item,reception,desired,source,replay,owner)
% Bind original emitted CSI port 3000 to the PRACTICAL pre-RF FFT operator.
% This is an isolation prerequisite, not an RSRP estimate/reference/error.
% No timing acquisition, OFDM operation, RF/channel replay or receiver input
% is performed. A multiport/resource component has no unique nonlinear
% port attribution in the retained desired-link samples and is not admitted.
evidence=struct('ContractVersion',"sixgr.csirs.emitted_reference_isolation/v1", ...
    'Available',false,'Status',"unavailable_no_original_CSI_reference_isolation", ...
    'Source',"original_completed_CSI_component_and_practical_preRF_operator", ...
    'ErrorIdentifier',"",'PowerComparisonPerformed',false, ...
    'IndependentRSRPAccuracyQualified',false,'ReferenceUsedByReceiver',false, ...
    'AdditionalTimingAcquisitions',0,'AdditionalOFDMDemodulations',0, ...
    'AdditionalRFExecutions',0,'AdditionalChannelExecutions',0);
if nargin==0, return; end
id='sixgr:truth:CSIRSIsolationOwnerIdentity';
assert(nargin==6 && isa(owner,'sixgr.truth.CoupledWaveformStream') && ...
    string(item.Kind)=="CSIRS" && isfield(item.Context,'ComponentID'),id, ...
    'Use the actual completed CSI owner and retained emitted component.');
p=item.Context.Prepared; c=p.Carrier;
assert(string(p.ExecutionStage)=="csirs_waveform_prepared_not_received" && ...
    owner.Events.NextSampleIndex>=p.ReceiveEndSampleExclusive,id, ...
    'The original CSI capture must be complete before independent audit.');
assert(reception.PhysicalMeasurementDemodulationReceiptAvailable,id, ...
    'The practical receiver must retain its original pre-RF demodulation operator.');
token=string(reception.PhysicalMeasurementDemodulationReceiptJSON);
digest=string(reception.PhysicalMeasurementDemodulationReceiptSHA256);
assert(isscalar(token)&&strlength(token)>0&&digest==sixgr.util.sha256Hex(char(token)),id, ...
    'The original practical demodulation token/hash must agree.');
r=jsondecode(token);
assert(any(string(r.ContractVersion)==["sixgr.csirs.physical_demodulation/v1","sixgr.csirs.physical_demodulation/v2"]) && ...
    string(r.Source)=="original_CSI_RS_physical_measurement_demodulation" && ...
    string(r.InputPlane)=="supplied_pre_composite_receiver_front_end_capture" && ...
    string(r.InputHashSerialization)=="WaveformHash.runtimeArray_class_dimensions_real_imag_double" && ...
    ~r.IndependentPowerReferenceAvailable && ~r.RSRPAccuracyQualified && ...
    ~r.AbsoluteObservationIdentityBound && ~r.ReceiveBranchLayoutQualified && ...
    r.AdditionalTimingAcquisitions==0 && r.AdditionalOFDMDemodulations==0,id, ...
    'Do not promote a reference claim or another plane into the original measurement receipt.');
evidence.PhysicalDemodulationReceiptSHA256=digest;
resources=r.Resources; if iscell(resources), resources=vertcat(resources{:}); end
maps=p.Tx.CSIRSRuntimeEvent.ResourceEvents;
evidence.ResourceCount=numel(resources);
evidence.LogicalPortCounts=double([resources.NumPorts]);
assert(numel(resources)==numel(maps),id,'Measured and prepared resource populations differ.');
if numel(resources)~=1
    evidence.Status="unavailable_multi_resource_component_not_independently_decomposed"; return;
end
if resources.NumPorts~=1 || maps.LogicalPortCount~=1
    evidence.Status="unavailable_multiport_component_not_independently_decomposed"; return;
end
if ~r.FFTSupport.Available
    evidence.Status="unavailable_original_preRF_FFT_support"; return;
end
ids=string({item.Planes.ReceiverID});
ip=find(ids==string(source.ReceiverID)+":pre_rf");
it=find(ids==string(item.Context.TransmitterPlane));
iq=find(ids==string(item.Context.DesiredReferencePlane));
assert(isscalar(ip)&&isscalar(it)&&isscalar(iq)&& ...
    item.Planes(iq).Observation==desired,id,'Retain original CSI capture instances.');
pre=item.Planes(ip).Observation; tx=item.Planes(it).Observation;
assert(pre.isComplete()&&tx.isComplete()&&desired.isComplete()&& ...
    pre.StartSample==p.ReceiveStartSample && pre.EndSampleExclusive==p.ReceiveEndSampleExclusive && ...
    pre.SampleRateHz==p.SampleRateHz && pre.sampleHash()==string(r.InputSHA256) && ...
    isequal(double(r.InputSize(:).'),[pre.EndSampleExclusive-pre.StartSample pre.NumReceiveAntennas]) && ...
    desired.StartSample==pre.StartSample && desired.EndSampleExclusive==pre.EndSampleExclusive && ...
    desired.SampleRateHz==pre.SampleRateHz && desired.NumReceiveAntennas==pre.NumReceiveAntennas && ...
    tx.StartSample==p.TransmitStartSample && tx.EndSampleExclusive==p.TransmitStartSample+p.NumSamples && ...
    tx.SampleRateHz==p.SampleRateHz,id,'Do not transplant a same-shaped desired or measurement window.');
assert(string(source.Source)=="actual_executed_link_contribution" && ...
    string(source.TransmitterID)==extractBefore(ids(it),':tx') && ...
    string(source.ReceiverID)==string(replay.ReceiverID) && ...
    source.StartSample==pre.StartSample && source.EndSampleExclusive==pre.EndSampleExclusive && ...
    ~source.ReceiverEstimatorInput && source.AdditionalRFExecutions==0 && ...
    source.AdditionalChannelExecutions==0,id,'Only the original desired-link contribution is admissible.');
assert(string(r.WaveformAmplitudeUnit)==string(replay.WaveformAmplitudeUnit) && ...
    string(r.WaveformAmplitudeUnit)==string(p.PowerContext.WaveformAmplitudeUnit) && ...
    r.WaveformAmplitudeUnitRecognized && r.NumReceiveChannels==pre.NumReceiveAntennas && ...
    isequal(double(r.ReceiveChannelIndices0(:).'),0:pre.NumReceiveAntennas-1),id, ...
    'Preserve actual executed units and original receive-column ordering.');
branch=sixgr.rf.validateReceiveBranchObservation(pre,replay, ...
    owner.Physical.receiveBranchLayout(string(source.ReceiverID)));
element=sixgr.rf.validateReceiveElementObservation(pre,replay, ...
    owner.Physical.receiveElementLayout(string(source.ReceiverID)));
if ~element.Available
    evidence.Status="unavailable_original_receive_element_execution_binding"; return;
end
records=owner.CSIRSTransmissions;
hit=find(string({records.ComponentID})==string(item.Context.ComponentID));
assert(isscalar(hit),id,'One original completed CSI transmission must own this component.');
executed=records(hit);
assert(string(executed.SignalFamily)=="CSI-RS" && ...
    executed.ServingCell==item.Context.ServingCell && executed.Slot==item.Context.Slot && ...
    executed.TransmitStartSample==tx.StartSample && executed.EndSampleExclusive==tx.EndSampleExclusive && ...
    executed.CommittedAtSample==tx.EndSampleExclusive && ...
    executed.SampleRateHz==pre.SampleRateHz && ...
    executed.PhysicalConfigurationEpoch==owner.Physical.ConfigurationEpoch && ...
    string(executed.TransmitterID)==string(source.TransmitterID) && ...
    string(executed.TransmitObservationSHA256)==tx.sampleHash() && ...
    executed.ResourceSetID==r.ResourceSetID && numel(executed.ExecutedResourceMaps)==1,id, ...
    'The reference must join the actual fully emitted CSI receipt, not queued intent.');
m=executed.ExecutedResourceMaps;
for name=["ResourceID","LogicalPortCount","WaveformPrecoderDigest","WaveformPrecoderMatrix","WaveformIndices","WaveformSymbols"]
    assert(isequaln(m.(name),maps.(name)),id,'Executed and prepared CSI mappings differ.');
end
assert(m.ResourceID==resources.ResourceID && ...
    isequal(m.LogicalPilotIndices,p.Tx.CSIRSIndices) && ...
    isequal(m.LogicalPilotSymbols,p.Tx.CSIRSSymbols) && ...
    string(resources.LogicalPilotIndicesSHA256)==hash(m.LogicalPilotIndices) && ...
    string(resources.LogicalPilotSymbolsSHA256)==hash(m.LogicalPilotSymbols) && ...
    executed.TXAmplitudeScale==p.PowerContext.AmplitudeScale,id, ...
    'Use the original logical port-3000 pilot and executed amplitude/map identity.');
% The component must itself contain ONLY this original CSI resource. Verify
% original native modulation hashes and exact map values; do not remodulate.
assert(numel(unique(m.WaveformIndices))==numel(m.WaveformIndices) && ...
    nnz(p.Tx.Grid)==numel(m.WaveformIndices) && ...
    isequal(p.Tx.Grid(m.WaveformIndices),m.WaveformSymbols) && ...
    string(m.WaveformPrecoderDigest)==sixgr.phy.mimo.MatrixContract.digest(m.WaveformPrecoderMatrix) && ...
    string(p.Tx.OFDMInfo.GridSHA256)==sixgr.phy.waveform.WaveformHash.numeric(p.Tx.Grid) && ...
    string(p.Tx.OFDMInfo.WaveformSHA256)==sixgr.phy.waveform.WaveformHash.numeric(p.Tx.Waveform) && ...
    p.RFExecutionDeferred && ~p.PowerContext.PAApplied && ...
    isequal(p.TransmitSamples,p.Tx.Waveform.*cast(p.PowerContext.AmplitudeScale,'like',p.Tx.Waveform)),id, ...
    'A composite or altered pre-RF component is not an isolated CSI port reference.');
K=12*double(c.NSizeGrid); L=double(c.SymbolsPerSlot);
index=double(m.LogicalPilotIndices(:));
assert(all(index>=1&index<=K*L) && all(index==fix(index)) && ...
    numel(unique(index))==numel(index) && ...
    isequal(size(m.WaveformPrecoderMatrix),[size(p.Tx.Grid,3) 1]),id, ...
    'Only original port 3000 is supported.');
for antenna=1:size(p.Tx.Grid,3)
    page=complex(zeros(K,L,'like',p.Tx.Grid));
    page(index)=m.WaveformPrecoderMatrix(antenna,1)*m.LogicalPilotSymbols(:);
    assert(isequal(page,p.Tx.Grid(:,:,antenna)),id, ...
        'The actual physical grid must contain only the original single-port pilot projection.');
end
base=unique(index-1,'sorted'); support=[mod(base,K) floor(base/K)];
assert(string(resources.Port3000SupportSHA256)==hash(support) && ...
    string(resources.PhysicalSupportSHA256)==hash(support) && ...
    string(r.FFTSupport.ResourceSupportSHA256)==hash(unique(support,'rows','sorted')),id, ...
    'The recorded physical support must be exactly the original port-3000 support.');
for name=["NCellID","NSizeGrid","NStartGrid","CyclicPrefix","NFrame","NSlot"]
    assert(isequal(string(r.Carrier.(name)),string(c.(name))),id,'Original carrier identity mismatch.');
end
assert(r.Carrier.SubcarrierSpacing_kHz==c.SubcarrierSpacing,id,'Original carrier spacing mismatch.');
f=r.FFTSupport; t=r.Timing; frequency=r.Frequency;
assert(string(f.RuntimeMATLABRelease)==string(version('-release')) && ...
    string(f.EngineUsed)=="canonical_nrOFDMDemodulate" && ...
    string(f.SampleCoordinateDomain)=="relative_to_original_preRF_capture_start_zero_based_half_open" && ...
    string(f.FFTWindowRule)=="symbol_start_plus_fix_CP_times_fraction" && ...
    f.OFDMWindowingSamples==0 && f.SampleRateHz==pre.SampleRateHz && ...
    f.Nfft==p.Tx.OFDMInfo.Nfft && f.SampleRateHz==f.Nfft*c.SubcarrierSpacing*1000 && ...
    ~t.OracleTimingUsed && ~t.ReceiverZeroPaddingUsed && ...
    isequaln(t.AppliedTimingCorrectionSamples,reception.PhysicalMeasurementReceiveTiming.AppliedTimingCorrectionSamples) && ...
    isequaln(t.DemodulatedSampleCount,reception.PhysicalMeasurementReceiveTiming.DemodulatedSampleCount),id, ...
    'Preserve the actual native pre-RF FFT timing; no padding or replacement acquisition.');
sixgr.phy.waveform.validateRecordedOFDMFFTAuthority(f,c,double(f.Nfft),double(f.SampleRateHz), ...
    double(f.CyclicPrefixFraction),L,0,string(r.ContractVersion)=="sixgr.csirs.physical_demodulation/v1");
tracking=reception.PhysicalMeasurementTrackingCorrection;
assert(string(frequency.PhaseOrigin)=="original_preRF_capture_start_zero_based" && ...
    frequency.CFOCorrectionApplied==tracking.CFOCorrectionApplied && ...
    string(frequency.Source)==string(tracking.Source) && string(frequency.Status)==string(tracking.Status),id, ...
    'Retain the original pre-RF CFO decision and phase origin, not post-RF compensation.');
if frequency.CFOCorrectionApplied
    assert(isscalar(frequency.CFOCorrectionApplied_Hz)&&isfinite(frequency.CFOCorrectionApplied_Hz)&& ...
        frequency.CFOCorrectionApplied_Hz==tracking.CFOCorrectionApplied_Hz,id,'Applied CFO changed.');
else
    assert(isempty(frequency.CFOCorrectionApplied_Hz)&&isnan(tracking.CFOCorrectionApplied_Hz),id, ...
        'Unavailable CFO remains unavailable rather than an invented applied zero.');
end
positions=mod(c.NSlot,c.SlotsPerSubframe)*L+(1:L);
cp=double(p.Tx.OFDMInfo.CyclicPrefixLengths(positions));
lengths=double(p.Tx.OFDMInfo.SymbolLengths(positions));
cp=cp(:).'; lengths=lengths(:).';
symbols=unique(support(:,2)).'; starts=[0 cumsum(lengths(1:end-1))];
assert(isequal(double(f.CyclicPrefixLengths(:).'),cp)&& ...
    isequal(double(f.SymbolLengths(:).'),lengths)&&all(lengths==cp+f.Nfft)&& ...
    isequal(double(f.SelectedSymbols0(:).'),symbols)&&sum(lengths)==t.DemodulatedSampleCount && ...
    isscalar(f.CyclicPrefixFraction)&&isfinite(f.CyclicPrefixFraction)&& ...
    f.CyclicPrefixFraction>=0&&f.CyclicPrefixFraction<=1,id,'Original FFT geometry mismatch.');
first=t.AppliedTimingCorrectionSamples+starts(symbols+1)+fix(cp(symbols+1)*f.CyclicPrefixFraction);
windows=[first(:) first(:)+f.Nfft]; retained=double(f.FFTIntervals);
if isvector(retained)&&numel(retained)==2, retained=reshape(retained,1,2); end
assert(isequal(retained,windows)&&all(windows(:,1)>=0)&& ...
    all(windows(:,2)<=pre.EndSampleExclusive-pre.StartSample),id,'Original FFT interval mismatch.');
request=struct('TransmitterID',string(source.TransmitterID),'ReceiverID',string(source.ReceiverID), ...
    'LinkID',string(source.LinkID),'ComponentID',string(item.Context.ComponentID), ...
    'ComponentSHA256',sixgr.phy.waveform.WaveformHash.numeric(p.TransmitSamples), ...
    'SampleRateHz',pre.SampleRateHz, ...
    'ConfigurationEpoch',executed.PhysicalConfigurationEpoch,'FFTIntervals',windows+pre.StartSample);
proof=sixgr.truth.proveEmittedComponentIsolation(owner.Events.ExecutionTrace,request);
evidence.Available=proof.Available; evidence.Status=proof.Status;
evidence.ObservationID=string(item.ID);
evidence.Transmission=struct('ComponentID',request.ComponentID,'ComponentSHA256',request.ComponentSHA256, ...
    'ComponentHashSerialization',"WaveformHash.numeric_element_count_real_imag_double", ...
    'TransmitStartSample',tx.StartSample,'TransmitEndSampleExclusive',tx.EndSampleExclusive, ...
    'TransmitObservationSHA256',tx.sampleHash(),'ResourceSetID',r.ResourceSetID, ...
    'ResourceID',m.ResourceID,'ReferencePort',3000,'WaveformPrecoderDigest',string(m.WaveformPrecoderDigest));
evidence.Measurement=struct('ObservationStartSample',pre.StartSample, ...
    'ObservationEndSampleExclusive',pre.EndSampleExclusive,'SampleRateHz',pre.SampleRateHz, ...
    'InputSHA256',pre.sampleHash(),'AlignedSHA256',string(r.AlignedSHA256), ...
    'GridSHA256',string(r.GridSHA256),'DesiredObservationSHA256',desired.sampleHash(), ...
    'Timing',t,'Frequency',frequency,'FFTSupport',f,'Port3000SupportSHA256',hash(support), ...
    'WaveformAmplitudeUnit',string(r.WaveformAmplitudeUnit));
evidence.ReceiveElementBinding=element;
evidence.ReceiveBranchBinding=branch; evidence.Isolation=proof;
% Emitted-component isolation is established in the original internal
% element-column plane. Keep optional stronger RF-branch binding separate;
% neither one establishes independent RSRP accuracy or absolute units here.
evidence.ReferencePlane=string(element.ReferencePlane);
evidence.Scope="isolated_single_resource_single_port_emitted_component_not_ideal_undistorted_RS";
evidence.IncludesOriginalTXRFNonlinearity=true; evidence.IncludesReceiverRF=false;
end

function value=hash(array)
value=sixgr.phy.waveform.WaveformHash.runtimeArray(array);
end
