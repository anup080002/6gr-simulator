function [values,evidence]=sharedNominalPhysicalChannelOnSupport(capture,prepared,source,captures,support)
% Independent postdecode nominal-linear operator on the original RX FFT.
% Executed RX delay/LO and receiver correction are retained. All other RF
% distortion and ICI/ISI remain errors; this is NOT RF-inclusive channel H.
assert(isa(prepared,'sixgr.link.PreparedDataTransmission') && prepared.Direction=="DL" && ...
    source.Source=="actual_executed_link_contribution" && ~source.ReceiverEstimatorInput && ...
    source.AdditionalChannelExecutions==0 && source.AdditionalRFExecutions==0 && ...
    source.ChannelReferenceCoverageComplete && iscell(captures) && ~isempty(captures), ...
    'sixgr:truth:PairedChannelReferenceSource','Use original completed desired-link channel captures, not another execution.');
fs=prepared.SampleRateHz; carrier=capture.Carrier; ofdm=capture.ReceiverOFDMInfo;
op=capture.ReceiverChannelOperator; K=12*carrier.NSizeGrid; L=carrier.SymbolsPerSlot;
nfft=double(ofdm.Nfft); base=captures{1}.Reference;
assert(fs==ofdm.SampleRate && fs==op.SampleRateHz && fs==nfft*carrier.SubcarrierSpacing*1000 && ...
    carrier.NSlot==prepared.Tx.Carrier.NSlot && carrier.NFrame==prepared.Tx.Carrier.NFrame && ...
    carrier.NSizeGrid==prepared.Tx.Carrier.NSizeGrid && carrier.NStartGrid==prepared.Tx.Carrier.NStartGrid && ...
    size(support,2)==2 && all(support(:,1)<K & support(:,2)<L), ...
    'sixgr:truth:PairedChannelReferenceClock','The native grid, carrier and original FFT clock must agree.');
segments=source.ReceiverClockExecution.ReceiveStreamExecutionSegments;
delay=NaN; hz=NaN;
for k=1:numel(segments)
    nodes=segments{k}.Execution.RX; node=nodes(string({nodes.ID})==source.ReceiverID);
    assert(isscalar(node) && all(isfield(node.Replay, ...
        {'InjectedTimingOffset_samples','CFOApplied','InjectedCFO_Hz','RFStageOrder'})), ...
        'sixgr:truth:PairedChannelReceiverClock','Retain actual RX-only clock execution.');
    r=node.Replay; d=double(r.InjectedTimingOffset_samples); f=0;
    if r.CFOApplied, f=double(r.InjectedCFO_Hz); end
    validateattributes(d,{'double'},{'scalar','integer','finite','nonnegative'});
    validateattributes(f,{'double'},{'scalar','real','finite'});
    order=split(string(r.RFStageOrder),'>');
    assert(any(order=="rx_timing") && any(order=="rx_lo_cfo") && ...
        find(order=="rx_timing",1)<find(order=="rx_lo_cfo",1), ...
        'sixgr:truth:PairedChannelReceiverClock','The retained operator requires executed delay before RX LO.');
    if k==1, delay=d; hz=f; end
    assert(d==delay && f==hz,'sixgr:truth:PairedChannelReceiverClock', ...
        'Changing clocks require their original phase history, not an inferred constant.');
end
assert(isfinite(delay) && isfinite(hz),'sixgr:truth:PairedChannelReceiverClock','Missing RX clock.');
next=base.StartSample; objectOffset=double(sixgr.util.structGet(base,'ObjectTimeOffsetSamples',0));
for k=1:numel(captures)
    c=captures{k}; r=c.Reference;
    assert(c.LinkID==source.LinkID && c.TX==source.TransmitterID && c.RX==source.ReceiverID && ...
        sixgr.channel.isAppliedChannelReference(r) && r.Source==base.Source && r.StateKey==base.StateKey && ...
        r.StartSample>=next && r.EndSampleExclusive>r.StartSample && r.SampleRateHz==fs && ...
        isequal(r.PathFilters,base.PathFilters) && r.NumTransmitAntennas==base.NumTransmitAntennas && ...
        r.NumReceiveAntennas==base.NumReceiveAntennas && r.NormalizeChannelOutputs==base.NormalizeChannelOutputs && ...
        size(r.PathGains,1)==r.EndSampleExclusive-r.StartSample && ~r.ReceiverEstimatorInput && ...
        r.AdditionalChannelExecutions==0 && ...
        (r.Source~="same_executed_NR_channel_path_gains_and_filters" || isfield(r,'ObjectTimeOffsetSamples')) && ...
        double(sixgr.util.structGet(r,'ObjectTimeOffsetSamples',0))==objectOffset, ...
        'sixgr:truth:PairedChannelReferenceCoverage','No gaps, alternate link/operator, replay or interpolated coefficients.');
    validateattributes(c.AppliedLargeScaleAmplitudeGain,{'numeric'},{'scalar','real','finite','positive'});
    next=r.EndSampleExclusive;
end
B=double(op.ReceiveCombiningMatrix); R=base.NumReceiveAntennas; T=base.NumTransmitAntennas;
assert(size(B,1)==R && size(B,2)==capture.GridShape(3) && all(isfinite(B),'all') && ...
    T==prepared.NumPhysicalTransmitAntennas,'sixgr:truth:PairedChannelReferenceMap', ...
    'Use actual physical dimensions and the actual receiver combiner.');
aligned=prepared.ReceiveStartSample+double(op.AppliedTimingCorrection_samples);
offset=aligned-delay-prepared.StartSample;
validateattributes(offset,{'double'},{'scalar','integer','finite'});
slotFirst=mod(double(carrier.NSlot),double(ofdm.SlotsPerSubframe))*L;
lengths=double(ofdm.SymbolLengths(slotFirst+(1:L))); cp=lengths-nfft;
starts=[0 cumsum(lengths(1:end-1))];
values=complex(zeros(size(B,2),T,size(support,1)));
fftFirst=zeros(size(support,1),1);
for symbol=unique(support(:,2)).'
    first=prepared.StartSample+starts(symbol+1);
    count=offset+floor(cp(symbol+1)*ofdm.CyclicPrefixFraction)+nfft;
    validateattributes(count,{'double'},{'scalar','integer','positive'});
    gains=complex(zeros(count,size(base.PathGains,2),T,R,'like',base.PathGains)); cursor=first;
    for k=1:numel(captures)
        c=captures{k}; r=c.Reference; a=max(first,r.StartSample); b=min(first+count,r.EndSampleExclusive);
        if b<=a, continue; end
        assert(a==cursor,'sixgr:truth:PairedChannelFFTReference','Every FFT sample needs its original channel coefficient.');
        at=(a-r.StartSample+1):(b-r.StartSample);
        assert(all(abs(double(r.SampleTimes_s(at))*fs-objectOffset-(a:b-1).')<1e-5), ...
            'sixgr:truth:PairedChannelReferenceClock','Native channel time and physical capture clock differ.');
        postClock=(a:b-1).'+delay;
        phase=exp(2i*pi/fs*(hz*postClock- ...
            double(op.CaptureOriginCFOCorrection_Hz)*(postClock-prepared.ReceiveStartSample)- ...
            double(op.AlignedOriginCFOCorrection_Hz)*(postClock-aligned)));
        gains((a-first+1):(b-first),:,:,:)=r.PathGains(at,:,:,:).* ...
            reshape(phase*c.AppliedLargeScaleAmplitudeGain,[],1,1,1);
        cursor=b;
    end
    assert(cursor==first+count,'sixgr:truth:PairedChannelFFTReference','No padding or extrapolation of missing reference samples.');
    h=sixgr.truth.receivedFFTChannelDiagonal(gains,base.PathFilters,nfft,cp(symbol+1),K,offset,ofdm.CyclicPrefixFraction);
    selected=find(support(:,2)==symbol);
    for q=selected.'
        values(:,:,q)=B'*reshape(h(support(q,1)+1,1,:,:),R,T);
    end
    fftFirst(selected)=aligned+starts(symbol+1)+floor(cp(symbol+1)*ofdm.CyclicPrefixFraction);
end
evidence=struct('Source',"same_executed_channel_samples_on_common_received_FFT", ...
    'ReferencePlane',"nominal_linear_effective_PDSCH_layer_on_actual_receiver_FFT_clock", ...
    'RFImpairmentsIncluded',false,'ReceiverEstimatorInput',false, ...
    'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0,'GainOrPhaseFitted',false, ...
    'ReceiverID',source.ReceiverID,'TransmitterID',source.TransmitterID,'LinkID',source.LinkID, ...
    'RecordedRXTimingOffset_samples',delay,'ExecutedRXCFO_Hz',hz, ...
    'ReceiverChannelOperator',op,'TimingOffsetRelativeTX_samples',offset, ...
    'ChannelObjectTimeOffsetSamples',objectOffset,'ChannelOutputNormalizationAlreadyInPathGains',true, ...
    'FFTStartSample',fftFirst,'FFTEndSampleExclusive',fftFirst+nfft, ...
    'ReferenceScope',"same_symbol_OFDM_diagonal_ICI_ISI_and_other_RF_distortion_remain_estimation_errors", ...
    'ExcludedRFOperators',"TX_DAC_IQ_PA_phase_noise_CFO_timing_and_RX_phase_noise_IQ_element_RF_ADC");
end
