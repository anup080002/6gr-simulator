function assertHARQFeedbackAvailable(rows,encodingSample,sampleRateHz)
% Causality at shared UCI preparation, NOT a complete N1/multiplexing budget.
% Never infer decoder availability from SourceSlot, DueSlot or ACK content.
validateattributes(encodingSample,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(sampleRateHz,{'numeric'},{'scalar','real','finite','positive'});
if istable(rows), rows=table2struct(rows); end
assert(isstruct(rows),'sixgr:truth:HARQTimingRowRequired','Use retained HARQ reservations.');
for k=1:numel(rows)
    row=rows(k); f=sixgr.truth.copyHARQReceiveTimingFields(row);
    token=string(f.DataReceiveTimingEvidenceJSON);
    assert(isscalar(token) && ~ismissing(token) && strlength(token)>0, ...
        'sixgr:truth:MissingUCIReceiveTiming', ...
        'Shared UCI requires actual DL receive-event timing for every HARQ-ACK reservation.');
    try
        e=jsondecode(token);
    catch
        error('sixgr:truth:InvalidUCIReceiveTiming','Malformed retained receive timing JSON.');
    end
    required={'ContractVersion','Direction','RNTI','GrantContextId','DataAbsoluteSlot', ...
        'ReceivedSymbolStartSample','ReceivedSymbolEndSampleExclusive', ...
        'ResultAvailableAtSample','SampleRateHz','Source','ProcessingBudgetIncluded', ...
        'ObservationStartSample','ObservationEndSampleExclusive','AppliedTimingCorrectionSamples'};
    assert(isstruct(e) && isscalar(e) && all(isfield(e,required)) && ...
        all(isfield(row,{'RNTI','SourceSlot','PUCCHGrantId'})), ...
        'sixgr:truth:InvalidUCIReceiveTiming','Incomplete receive-event/reservation identity.');
    numbers=[e.ReceivedSymbolStartSample e.ReceivedSymbolEndSampleExclusive ...
        e.ResultAvailableAtSample e.ObservationStartSample e.ObservationEndSampleExclusive ...
        e.AppliedTimingCorrectionSamples e.DataAbsoluteSlot];
    assert(isnumeric(numbers) && isreal(numbers) && numel(numbers)==7 && ...
        all(isfinite(numbers)) && all(numbers>=0) && all(numbers==fix(numbers)) && ...
        string(e.ContractVersion)=="received_data_symbol_timing/v1" && ...
        string(e.Direction)=="DL" && e.RNTI==row.RNTI && ...
        e.DataAbsoluteSlot==row.SourceSlot-1 && strlength(string(e.GrantContextId))>0 && ...
        strlength(string(row.PUCCHGrantId))>0 && ...
        e.SampleRateHz==sampleRateHz && f.DataReceiveSampleRateHz==sampleRateHz && ...
        e.ReceivedSymbolStartSample==f.DataReceiveSymbolStartSample && ...
        e.ReceivedSymbolEndSampleExclusive==f.DataReceiveSymbolEndSampleExclusive && ...
        e.ResultAvailableAtSample==f.DataDecodeAvailableAtSample && ...
        string(e.Source)==string(f.DataReceiveTimingSource) && ...
        string(e.Source)=="actual_received_reference_alignment_and_executed_OFDM_symbol_lengths" && ...
        isequal(e.ProcessingBudgetIncluded,false) && ...
        e.ReceivedSymbolStartSample>=e.ObservationStartSample+e.AppliedTimingCorrectionSamples && ...
        e.ReceivedSymbolEndSampleExclusive>e.ReceivedSymbolStartSample && ...
        e.ReceivedSymbolEndSampleExclusive<=e.ObservationEndSampleExclusive && ...
        e.ResultAvailableAtSample>=e.ObservationEndSampleExclusive, ...
        'sixgr:truth:InvalidUCIReceiveTiming', ...
        'HARQ-ACK timing must retain the original DL receiver, sample domain and source allocation.');
    assert(e.ResultAvailableAtSample<=encodingSample, ...
        'sixgr:truth:FutureHARQFeedbackAtUCIEncoding', ...
        'The DL decoder result is not available at this UCI encoding event.');
end
end
