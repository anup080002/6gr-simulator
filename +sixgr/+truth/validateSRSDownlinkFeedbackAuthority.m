function validateSRSDownlinkFeedbackAuthority(cfg)
% Joint acquisition does not authorize copying UL quality/codebook into DL.
source = lower(strtrim(string(sixgr.util.structGet(cfg, ...
    'phy.linkAdaptation.cqiSource', ''))));
if isscalar(source) && source == "csi_feedback"
    return;
end
if isscalar(source) && source == "srs_based"
    error('sixgr:truth:UnqualifiedSRSDownlinkPrediction', ...
        ['link_adaptation.cqi_source=srs_based requires a calibrated reciprocal ' ...
        'channel, DL transmit EPRE, UE noise/interference and DL precoder evaluation. ' ...
        'The current SRS producer supplies UL quality/TPMI only; copying these ' ...
        'into DL or applying a scalar backoff is not a qualified DL prediction.']);
end
error('sixgr:truth:UnsupportedDownlinkCQISource', ...
    'An explicit supported phy.linkAdaptation.cqiSource is required; received %s.', ...
    char(join(source(:), ',')));
end
