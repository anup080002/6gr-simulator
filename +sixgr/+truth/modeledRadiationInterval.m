function T=modeledRadiationInterval(replay,base,nativeHashes)
% Compact original-owner interval; field arrays live once in the library.
row=struct('EndpointID',"",'Direction',"",'StartSample',NaN,'EndSampleExclusive',NaN, ...
    'SampleRateHz',NaN,'SampleCount',NaN,'ConfigurationEpoch',NaN,'PhysicalChainCount',NaN, ...
    'InstallationSHA256',"",'FieldSHA256',"",'RFInputWaveformSHA256',"",'RFOutputWaveformSHA256',"", ...
    'SpatialMatrixSHA256',"",'InternalMeanSquare_mW',NaN,'ModelTRP_mW',NaN, ...
    'SampledPeakModelEIRP_mW',NaN,'ModelResultSHA256',"",'ReceiptJSON',"",'ReceiptSHA256',"", ...
    'NativeInstallationReceiptSHA256sJSON',"",'NativeChannelInstallationMatched',false, ...
    'ModelIntegratedRadiationVerified',true,'AcceptedFeedPowerQualified',false, ...
    'HardwareConformanceVerified',false,'PowerRenormalizationApplied',false, ...
    'CoordinateFrame',"installed_array_local_coordinates", ...
    'FrequencyScope',"frequency_flat_installed_carrier_field_model", ...
    'Source',"canonical_shared_TX_RF_owner_completed_interval");
T=struct2table(row); T=T([],:); if nargin==0, return; end
assert(height(base)==1&&base.Role=="TX"&&isfield(replay,'ModeledRadiation'), ...
    'sixgr:truth:ModeledRadiationMissing','Require the original TX owner receipt.');
r=replay.ModeledRadiation;
for name=["EndpointID","Direction","StartSample","EndSampleExclusive","SampleRateHz","SampleCount","ConfigurationEpoch"]
    row.(name)=base.(name);
end
for name=["PhysicalChainCount","InstallationSHA256","FieldSHA256","RFInputWaveformSHA256", ...
        "RFOutputWaveformSHA256","SpatialMatrixSHA256","InternalMeanSquare_mW","ModelTRP_mW", ...
        "SampledPeakModelEIRP_mW","ModelResultSHA256","ReceiptSHA256"]
    row.(name)=r.(name);
end
row.ReceiptJSON=string(jsonencode(r));
row.NativeInstallationReceiptSHA256sJSON=string(jsonencode(reshape(string(nativeHashes),[],1)));
row.NativeChannelInstallationMatched=~isempty(nativeHashes);
T=struct2table(row);
end
