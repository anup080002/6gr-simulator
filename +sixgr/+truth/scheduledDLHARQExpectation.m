function expected=scheduledDLHARQExpectation(grant,identity,committedAtSample)
% gNB-side scheduled expectation, never UE reception or an ACK/NACK value.
% The caller must separately prove that identity was physically transmitted.
% Keeping this independent of ControlDecodeOk is essential for missed DCI.
expected=struct([]);
assert(string(identity.Direction)=="DL" && upper(string(grant.Direction))=="DL", ...
    'sixgr:truth:DLFeedbackExpectationDirection','Only a DL transmission creates this expectation.');
assert(isfield(grant,'TimingDecision') && isstruct(grant.TimingDecision) && ...
    isscalar(grant.TimingDecision) && isfield(grant.TimingDecision,'HARQACKRequired'), ...
    'sixgr:truth:DLFeedbackExpectationTiming','Retain the actual canonical HARQ timing decision.');
sixgr.phy.grant.assertGrantTimingIdentity(grant,'DL');
t=grant.TimingDecision;
assert(isequal(t.Valid,true),'sixgr:truth:DLFeedbackExpectationTiming','The issued timing decision must be valid.');
if ~t.HARQACKRequired, return; end
validateattributes(committedAtSample,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
assert(grant.RNTI==identity.RNTI && grant.UEIndex==identity.UEIndex && ...
    string(grant.PHYGrant.GrantContextId)==string(identity.PHYGrantContextId) && ...
    grant.Slot==t.DataAbsoluteSlot+1, ...
    'sixgr:truth:DLFeedbackExpectationIdentity','Schedule, physical contribution and absolute data clock must agree.');
assert(committedAtSample>identity.StartSample && committedAtSample<=identity.EndSampleExclusive, ...
    'sixgr:truth:DLFeedbackExpectationBeforeTX','An expectation commit must follow an actual active TX sample.');
validateattributes(t.FeedbackAbsoluteSlot,{'numeric'},{'scalar','finite','integer','nonnegative'});
assert(t.FeedbackAbsoluteSlot>=t.DataAbsoluteSlot && ...
    isequal(t.HARQACKDecision.Valid,true), ...
    'sixgr:truth:DLFeedbackExpectationTiming','Retain the valid feedback symbol/tick decision.');
pid=double(grant.HARQ.HarqID);
validateattributes(pid,{'numeric'},{'scalar','finite','integer','nonnegative'});
% Parsing the gNB's own packed bits is schedule evidence, NOT received DCI.
% Do not infer PRI from defaults or an unrelated current configuration.
packed=sixgr.phy.pdcch.decodeDCIPayload(grant.DCI.Bits,grant.DCI.Format,grant.DCI.ContextData);
assert(isfield(packed.Fields,'pucch_resource_indicator'), ...
    'sixgr:truth:DLFeedbackExpectationPRI','The scheduled DL DCI must own its feedback resource indicator.');
pri=double(packed.Fields.pucch_resource_indicator);
if isfield(grant,'PUCCHResourceIndicator')
    assert(isequal(double(grant.PUCCHResourceIndicator),pri), ...
        'sixgr:truth:DLFeedbackExpectationPRI','Scheduled PRI differs from its packed DCI.');
end
expected=struct('TransmissionID',string(identity.TransmissionID), ...
    'PHYGrantContextId',string(identity.PHYGrantContextId), ...
    'UEIndex',double(identity.UEIndex),'RNTI',double(identity.RNTI), ...
    'HARQProcess',pid,'NDI',logical(grant.HARQ.NDI),'RV',double(grant.HARQ.RV), ...
    'ControlAbsoluteSlot0',double(t.ControlAbsoluteSlot), ...
    'DataAbsoluteSlot0',double(t.DataAbsoluteSlot), ...
    'FeedbackAbsoluteSlot0',double(t.FeedbackAbsoluteSlot), ...
    'ScheduledCCID',string(t.ScheduledCCID), ...
    'ScheduledPRI',pri,'ScheduledDCI',grant.DCI, ...
    'FeedbackTimingDecision',t.HARQACKDecision, ...
    'TXCommittedAtSample',double(committedAtSample), ...
    'Source',"gnb_transmitted_schedule_expectation_not_received_UCI", ...
    'Status',"awaiting_physical_feedback_observation");
% No assumed bit count: one/two TB, spatial bundling, codebook type and DAI
% must be resolved by the configured feedback-codebook policy, not guessed
% here from the number of successfully received PDSCH rows.
end
