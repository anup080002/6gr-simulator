function [key,identity]=scheduledULHARQReceiverKey(cfg,grant)
% Stable scalar-TB gNB identity, not a UE payload or per-RV assignment hash.
% The caller separately binds this scheduled grant to its physical command
% and completed receive window. This key alone is not reception evidence.
sixgr.phy.grant.assertGrantTimingIdentity(grant,'UL');
installed=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,'0_1');
packed=sixgr.phy.pdcch.DCIContext(grant.DCI.ContextData);
wire=sixgr.phy.pdcch.decodeDCIPayload(grant.DCI.Bits,'0_1',packed);
assert(installed.Digest==packed.Digest && grant.RNTI==installed.Data.RNTIValue, ...
    'sixgr:truth:ULHARQReceiverContextMismatch', ...
    'The receiver HARQ identity must belong to this installed scheduled UL context.');
h=grant.HARQ;
assert(isstruct(h) && isscalar(h) && all(isfield(h,{'HarqID','NDI','NDIEpoch','RV'})), ...
    'sixgr:truth:ULHARQReceiverIdentityRequired','Retain explicit scheduled process, NDI, epoch and RV.');
validateattributes(grant.UEIndex,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(grant.ServingCell,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(h.HarqID,{'numeric'},{'scalar','real','finite','integer','nonnegative','<',installed.Data.HARQProcessCount});
validateattributes(h.NDIEpoch,{'numeric'},{'scalar','real','finite','integer','nonnegative','<=',flintmax});
assert((isnumeric(h.NDI)||islogical(h.NDI)) && isreal(h.NDI) && ...
    isscalar(h.NDI) && any(h.NDI==[0 1]) && ...
    isnumeric(h.RV) && isreal(h.RV) && isscalar(h.RV) && any(h.RV==(0:3)) && ...
    wire.Fields.harq_process==h.HarqID && wire.Fields.ndi==h.NDI && wire.Fields.rv==h.RV, ...
    'sixgr:truth:ULHARQReceiverWireIdentityMismatch', ...
    'The retained HARQ process/NDI/RV must match the actual scheduled DCI payload.');
identity=struct('Direction',"UL",'UEIndex',double(grant.UEIndex), ...
    'RNTI',double(grant.RNTI),'ServingCell',double(grant.ServingCell), ...
    'InstalledContextDigest',installed.Digest,'HARQProcess',double(h.HarqID), ...
    'NDI',logical(h.NDI),'NDIEpoch',double(h.NDIEpoch),'CodewordIndex',1);
% The installed digest includes carrier/BWP and configuration epoch. RV,
% resource allocation and slot may change for the same retained TB.
key="gNB-UL-TB-"+sixgr.phy.pucch.PUCCHUtil.hash(identity);
end
