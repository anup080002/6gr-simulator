function state=commitSharedPUCCHTransmission(state,item)
% Record UE physical TX independently of the subsequent gNB receiver result.
% This is the MAC event boundary, not an SR trigger or a received ACK/CSI.
assert(isfield(state,'SharedWaveformStream') && item.Kind=="PUCCHTX", ...
    'sixgr:truth:SharedPUCCHTXOwnerRequired','An actual shared-owner PUCCH TX event is required.');
owner=state.SharedWaveformStream;
identity=sixgr.truth.preparedPUCCHTransmissionIdentity( ...
    item.Context.Prepared,item.UE,item.Context.TransmissionIdentity.ObservationID);
assert(isequaln(identity,item.Context.TransmissionIdentity) && ...
    identity.RFConfigurationEpoch==owner.Physical.ConfigurationEpoch, ...
    'sixgr:truth:SharedPUCCHTXIdentityMismatch','Retain the executed preparation and clock epoch.');
records=owner.PUCCHTransmissions;
hit=arrayfun(@(r)r.Identity.TransmissionID==identity.TransmissionID,records);
assert(nnz(hit)==1 && isequaln(records(hit).Identity,identity) && ...
    records(hit).FirstActiveSample==item.Context.FirstActiveSample && ...
    records(hit).CommittedAtSample==item.Context.FirstActiveSample+1 && ...
    records(hit).CommittedAtSample<=owner.Events.NextSampleIndex && ...
    isequaln(records(hit).WaveformToElementMatrix,item.Context.WaveformToElementMatrix), ...
    'sixgr:truth:SharedPUCCHTXNotExecuted','No matching active PUCCH sample has physically executed.');
ledger=sixgr.util.structGet(state,'SharedPUCCHTXLedger',{});
assert(~any(cellfun(@(r)r.Identity.TransmissionID==identity.TransmissionID,ledger)), ...
    'sixgr:truth:DuplicateSharedPUCCHTXCommit','A physical PUCCH transmission is committed exactly once.');
ledger{end+1,1}=struct('Identity',identity, ...
    'TransmitOccupancy',records(hit).TransmitOccupancy, ...
    'TransmitPopulationIdentity',sixgr.truth.transmitOccupancyPopulation(state,item.Context.Prepared.InputConfig), ...
    'FirstActiveSample',records(hit).FirstActiveSample, ...
    'CommittedAtSample',records(hit).CommittedAtSample, ...
    'WaveformToElementMatrix',records(hit).WaveformToElementMatrix, ...
    'Source',"actual_shared_PUCCH_transmission_started_not_receiver_outcome");
assignment=item.Context.Prepared.RequestBinding.Assignment;
powerState=assignment.PowerControlState.Data;
mode=string(sixgr.util.structGet(item.Context.Prepared.InputConfig, ...
    'validation.pucch_resources.power_control.closed_loop_mode','configured'));
if mode=="received_dci"
    assert(isfield(powerState,'ReceivedPowerProposal') && ...
        numel(state.SharedReceivedPUCCHPowerOwners)>=item.UE, ...
        'sixgr:truth:PUCCHTransmittedPowerBinding','Actual TX must retain its original received-power proposal.');
    proposal=powerState.ReceivedPowerProposal;
    tx=struct('TransmissionID',string(identity.TransmissionID),'ObservationID',string(identity.ObservationID), ...
        'AssignmentDigest',string(identity.AssignmentDigest),'PowerProposalDigest',string(proposal.Digest), ...
        'FirstActiveSample',double(records(hit).FirstActiveSample), ...
        'CommittedAtSample',double(records(hit).CommittedAtSample),'SampleRateHz',identity.SampleRateHz, ...
        'ClockEpoch',identity.RFConfigurationEpoch,'SubcarrierSpacingKHz',double(item.Context.Prepared.Tx.Carrier.SubcarrierSpacing), ...
        'Source',"actual_shared_PUCCH_transmission_started_not_receiver_outcome");
    emitted=item.Context.Prepared.Tx.Power;
    power=struct('PowerProposalDigest',string(proposal.Digest),'ClosedLoopAdjustment_dB',powerState.ClosedLoopAdjustmentdB, ...
        'P0_dBm',powerState.P0dBm,'RequestedPower_dBm',emitted.RequestedPowerdBm, ...
        'AppliedPower_dBm',emitted.AppliedPowerdBm,'PCMAX_dBm',powerState.PCMAXdBm, ...
        'MinimumPower_dBm',-Inf,'Source',"original_transmitted_PUCCH_power_state");
    state.SharedReceivedPUCCHPowerOwners{item.UE}= ...
        state.SharedReceivedPUCCHPowerOwners{item.UE}.commitTransmission(proposal,tx,power);
    ledger{end}.ReceivedPowerHistory=state.SharedReceivedPUCCHPowerOwners{item.UE}.History{end};
else
    assert(mode=="configured" && ~isfield(powerState,'ReceivedPowerProposal'), ...
        'sixgr:truth:PUCCHTransmittedPowerBinding','Power owner mode must match the emitted assignment.');
end
state.SharedPUCCHTXLedger=ledger;
end
