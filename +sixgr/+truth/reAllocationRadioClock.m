function [sfn,slotWithinFrame0]=reAllocationRadioClock(absoluteSlot0,slotsPerFrame)
% REALLOCATIONRADIOCLOCK Label exact allocation coordinates, not a new epoch.
% The caller supplies the clock owning absoluteSlot0: carrier slots for
% carrier/PRACH-origin rows, native SSB slots for native SS/PBCH rows.
% Absolute coordinates remain unchanged; SFN alone wraps every 1024 frames.
assert(isa(absoluteSlot0,'double') && isreal(absoluteSlot0) && ...
    (isvector(absoluteSlot0) || isempty(absoluteSlot0)) && ...
    all(isfinite(absoluteSlot0(:))) && all(absoluteSlot0(:)>=0) && ...
    all(absoluteSlot0(:)<flintmax) && all(absoluteSlot0(:)==fix(absoluteSlot0(:))), ...
    'sixgr:truth:InvalidREAllocationClock', ...
    'Allocation slots must be exact nonnegative zero-based double coordinates.');
assert(isa(slotsPerFrame,'double') && isreal(slotsPerFrame) && ...
    (isscalar(slotsPerFrame) || isequal(size(slotsPerFrame),size(absoluteSlot0))) && ...
    all(isfinite(slotsPerFrame(:))) && all(slotsPerFrame(:)>=1) && ...
    all(slotsPerFrame(:)<flintmax) && all(slotsPerFrame(:)==fix(slotsPerFrame(:))), ...
    'sixgr:truth:InvalidREAllocationClock', ...
    'Supply the original positive integer slots-per-frame for each allocation clock.');
sfn=zeros(size(absoluteSlot0)); slotWithinFrame0=zeros(size(absoluteSlot0));
if isempty(absoluteSlot0), return; end
if isscalar(slotsPerFrame), slotsPerFrame=repmat(slotsPerFrame,size(absoluteSlot0)); end
for count=reshape(unique(slotsPerFrame),1,[])
    selected=slotsPerFrame==count;
    [~,~,frame0,slot0]=sixgr.time.canonicalSlotToFrameSlot(absoluteSlot0(selected)+1,count);
    sfn(selected)=mod(frame0,1024);
    slotWithinFrame0(selected)=slot0;
end
end
