function state = recordSharedQCLTimingReference(state,p,observation,out,ue,cellIndex)
% Receiver evidence only; nominal occasion is from the shared OFDM clock.
policy=sixgr.util.structGet(p.ReceiverConfig,'phy.pdsch.qclTCI',struct());
if ~logical(sixgr.util.structGet(policy,'enabled',false)), return; end
if ~out.DetectionSuccess || ~out.TRSTimingEstimateAvailable || ...
        ~out.TRSTimingEstimateUsable || ~observation.isComplete(), return; end
mapping=p.Tx.ResourceMappingTable;
timingSourceResourceID=double(sixgr.util.structGet(policy, ...
    'timing_source_resource_id',sixgr.util.structGet(policy,'source_resource_id',NaN)));
assert(isfinite(timingSourceResourceID) && timingSourceResourceID>=0 && ...
    timingSourceResourceID==fix(timingSourceResourceID), ...
    'sixgr:qcl:MissingTimingSourceResource', ...
    'QCL timing transfer requires an installed TRS resource identity.');
assert(ismember('NZPCSIRSResourceID',mapping.Properties.VariableNames) && ...
    any(mapping.NZPCSIRSResourceID==timingSourceResourceID), ...
    'sixgr:qcl:MissingSourceResource','QCL source must occur in the actual TRS mapping.');
slot0=double(p.Tx.FirstSlot0Based);
scs=double(p.Tx.GridSlots(1).Carrier.SubcarrierSpacing);
nominalStart=slot0*1e-3*15/scs*observation.SampleRateHz;
assert(abs(nominalStart-round(nominalStart))<1e-6, ...
    'sixgr:qcl:ClockMismatch','Reference occasion must lie on the OFDM sample clock.');
reference=struct('UEIndex',double(ue),'ServingCellIndex',double(cellIndex), ...
    'SourceResourceID',timingSourceResourceID, ...
    'ConfigurationEpoch',double(policy.configuration_epoch), ...
    'SourceSlot0',slot0,'AvailableAtSample',observation.EndSampleExclusive, ...
    'SampleRateHz',observation.SampleRateHz, ...
    'TimingPhaseSamples',observation.StartSample+double(out.EstimatedTimingOffset_samples)-round(nominalStart), ...
    'Source',"received_nzp_csi_rs_trs_timing_estimator", ...
    'SourceConfigHash',string(p.StrictConfig.ConfigHash));
if isfield(sixgr.util.structGet(p.ReceiverConfig,'phy.pdcch.operatorControl',struct()),'connected_dci')
    context=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(p.ReceiverConfig,'1_1');
    reference.RRCServingCellIndex=double(context.Data.ScheduledServingCell);
end
references=sixgr.util.structGet(state,'SharedQCLTimingReferences',{});
references{ue}=reference;
state.SharedQCLTimingReferences=references;
end
