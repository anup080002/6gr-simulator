function res=bindSharedDLCSICompletion(res,prepared,observation,owner,state,ue)
% Bind actual receiver CSI before the coordinator commits any DL result.
% Empty CSI tables stay empty. This is chronology/provenance, not RF repair.
% Installation remains a separate acquisition-time action. Completion only
% binds the ORIGINAL prepared receiver configuration to current authority;
% missing, changed or post-observation installations remain diagnostic.
assert(isstruct(res) && isscalar(res), ...
    'sixgr:truth:CSICompletionResultRequired','Retain one actual completed DL result.');
if ~isfield(res,'CSIRSTrialTable'), return; end
assert(istable(res.CSIRSTrialTable),'sixgr:truth:CSIRSClockTableRequired', ...
    'CSI result evidence must be a table, including when it is empty.');
if isempty(res.CSIRSTrialTable), return; end
assert(isa(owner,'sixgr.truth.CoupledWaveformStream') && isscalar(owner) && ...
    isa(prepared,'sixgr.link.PreparedDataTransmission') && isscalar(prepared) && ...
    prepared.Direction=="DL" && ...
    isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && isscalar(observation), ...
    'sixgr:truth:CSICompletionOwnerRequired', ...
    'Shared CSI must use its actual DL prepared transmission, receive capture and physical owner.');
assert(nargin==6 && isstruct(state) && isscalar(state) && ...
    isequal(sixgr.util.structGet(state,'SharedWaveformStream',[]),owner), ...
    'sixgr:truth:CSICompletionStateRequired', ...
    'Bind installation evidence from the completion state owning this physical stream.');
validateattributes(ue,{'double'},{'scalar','real','finite','integer','positive','<=',state.NumUsers});
cfg=prepared.ReceiverConfig;
preparedUE=sixgr.util.structGet(cfg,'lls6g.userContext.UEIndex',NaN);
preparedCell=sixgr.util.structGet(cfg,'lls6g.userContext.RuntimeServingCell',NaN);
assert(isnumeric(preparedUE) && isscalar(preparedUE) && isreal(preparedUE) && ...
    isfinite(preparedUE) && preparedUE==ue && ...
    isnumeric(preparedCell) && isscalar(preparedCell) && isreal(preparedCell) && ...
    isfinite(preparedCell) && preparedCell>=1 && preparedCell==fix(preparedCell), ...
    'sixgr:truth:CSICompletionReceiverIdentity', ...
    'Retain the original prepared UE and serving-cell identity, not a current scheduler substitution.');
assert(isfield(res,'ExecutionStage') && string(res.ExecutionStage)=="received_shared_stream_completed" && ...
    isfield(res,'ReceiveTiming'), ...
    'sixgr:truth:CSICompletionNotReceived','A prepared or standalone result cannot claim shared CSI completion.');
available=owner.Events.NextSampleIndex;
assert(~owner.Events.Faulted && ~owner.Physical.Faulted && ...
    owner.Physical.NextSampleIndex==available && ...
    observation.SampleRateHz==owner.SampleRateHz && prepared.SampleRateHz==owner.SampleRateHz && ...
    observation.EndSampleExclusive<=available, ...
    'sixgr:truth:CSICompletionClockMismatch', ...
    'CSI publication must follow the actual complete capture on one nonfaulted physical/event clock.');
bound=sixgr.truth.bindReceivedCSIRSClock(res.CSIRSTrialTable,prepared,observation, ...
    res.ReceiveTiming,available,owner.Physical.ConfigurationEpoch);
% The embedded producer already supplies UEIndex; ServingCell may be absent
% in its older schema. Bind it from the immutable prepared receiver context,
% never from the current serving-cell selection after handover/reacquisition.
identity=struct('UEIndex',ue,'ServingCell',double(preparedCell));
for name=string(fieldnames(identity)).'
    expected=repmat(identity.(name),height(bound),1);
    if ismember(name,bound.Properties.VariableNames)
        actual=bound.(name);
        assert(isnumeric(actual) && isreal(actual) && isequal(actual,expected), ...
            'sixgr:truth:CSICompletionReceiverIdentity', ...
            'Existing CSI receiver identity cannot be overwritten at completion.');
    else
        bound.(name)=expected;
    end
end
stamped=cell(height(bound),1);
for row=1:height(bound)
    sixgr.truth.csirsMeasurementAvailability(bound(row,:),true);
    stamped{row}=sixgr.truth.DLMeasurementInstallation.stamp(state,bound(row,:),cfg,ue,"CSI-RS");
    % Idempotent repeat is allowed; an existing installation/configuration
    % binding cannot be silently retagged when the live state changes.
    names=intersect(string(bound.Properties.VariableNames), ...
        string(stamped{row}.Properties.VariableNames));
    names=names(startsWith(names,"DLMeasurement"));
    for name=names
        assert(isequaln(bound.(name)(row,:),stamped{row}.(name)), ...
            'sixgr:truth:CSICompletionInstallationConflict', ...
            'Retain original CSI installation evidence; do not overwrite it with a later installation.');
    end
end
res.CSIRSTrialTable=vertcat(stamped{:});
end
