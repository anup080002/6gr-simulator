function validatePortableCSIRankSelectionEvidence(d,prepared,reception,csi)
% Original-operand replay of an explicit implementation policy. No PHY/RF replay.
% This validates arithmetic/identity, not independent selection quality or BLER.
id='sixgr:truth:CSIRankSelectionEvidenceMismatch';
cfg=prepared.ReceiverConfig; state=reception.CSIMeasurementState;
request=cfg.phy.csi.reportConfiguration; runtime=d.Configuration;
% Match the ORIGINAL producer clock, which may legitimately be later than
% acquisition but must not be supplied by the returned decision itself.
expectedSlot=double(sixgr.util.structGet(cfg,'runtime.currentSlot',state.Slot));
assert(isnumeric(runtime.CurrentSlot)&&isreal(runtime.CurrentSlot)&&isscalar(runtime.CurrentSlot)&& ...
    isfinite(runtime.CurrentSlot)&&runtime.CurrentSlot==fix(runtime.CurrentSlot)&& ...
    isscalar(expectedSlot)&&isfinite(expectedSlot)&&expectedSlot==fix(expectedSlot)&& ...
    expectedSlot>=0&&isequal(double(runtime.CurrentSlot),expectedSlot),id, ...
    'Selection clock differs from the original prepared receiver configuration.');
state.validateAt(expectedSlot);
if isa(state.InterferenceCovariance,'sixgr.phy.mimo.InterferenceCovarianceState')
    state.InterferenceCovariance.validateAt(expectedSlot);
end

assert(string(d.ContractVersion)=="sixgr.portable_TypeI_MMSE_rank_decision/v1" && ...
    string(cfg.phy.csi.selectionBackend)=="portable_typeI_mmse",id,'Wrong original selection backend.');
assert(isequaln(runtime.ReportConfiguration,request) && ...
    isequaln(runtime.PortableCQIModel,cfg.phy.csi.portableCQIModel) && ...
    string(runtime.CQITable)==string(cfg.phy.csi.cqiTable) && ...
    upper(string(runtime.Receiver))==upper(string(cfg.phy.rx.detector)),id, ...
    'Returned policy must equal original installed policy.');
assert(isequal(double(runtime.RankDomain(:)),double(cfg.phy.csi.rankDomain(:))),id, ...
    'Portable v1 requires an explicit installed rank domain equal to searched domain.');
assert(d.MeasurementID==state.MeasurementID && d.MeasurementDigest==state.Digest && ...
    d.MeasurementSlot==state.Slot && d.ReportConfigurationEpoch==request.Epoch && ...
    string(d.ReportConfigID)==string(request.ReportConfigID),id,'Original CSI identity changed.');
assert(state.Slot==prepared.Carrier.NFrame*prepared.Carrier.SlotsPerFrame+prepared.Carrier.NSlot+1, ...
    id,'Original receiver clock differs from the retained measurement.');
assert(isequaln(reception.CSIRSNoiseVar,state.NoiseVariance),id,'Original measured noise changed.');
assert(d.ChannelSHA256==sixgr.phy.waveform.WaveformHash.runtimeArray(reception.CSIRSChannelEstimate), ...
    id,'Original full received channel changed.');
% Retained producer operands only: no receiver or rank/PMI search is rerun.
R=state.InterferenceCovariance; inc=state.InterferenceCovarianceIncludesNoise;
if isa(R,'sixgr.phy.mimo.InterferenceCovarianceState'), inc=R.IncludesNoise; R=R.Matrix; end
if isempty(R), R=double(state.NoiseVariance)*eye(size(reception.CSIRSChannelEstimate,3));
elseif ~inc, R=R+double(state.NoiseVariance)*eye(size(R,1)); end
assert(d.DisturbanceSHA256==sixgr.phy.waveform.WaveformHash.runtimeArray(R),id,'Original disturbance changed.');
assert(~d.DecodedBLERAvailable && ~d.IndependentSelectionQualityVerified && ...
    ~d.StandardizedAccuracyQualified && d.AdditionalRankSearches==0,id,'Unsupported qualification/search claim.');
ranks=double(d.RankDomain(:).');
assert(isequal(ranks,double(runtime.RankDomain(:).'))&& ...
    ~isempty(ranks)&&isequal(ranks,unique(ranks,'sorted'))&& ...
    all(ismember(ranks,1:min(4,size(reception.CSIRSChannelEstimate,3)))),id, ...
    'Receipt searched domain differs from original installed policy.');
assert(string(d.Classification)=="IMPLEMENTATION_POLICY"&& ...
    string(d.ReferencePlane)=="received_channel_and_measured_disturbance"&& ...
    d.RankSearchCallCount==1&&d.AdditionalRankSearches==0,id,'Invalid policy/plane/search claim.');
for flag=["DecodedBLERAvailable","IndependentSelectionQualityVerified","StandardizedAccuracyQualified"]
    assert(islogical(d.(flag))&&isscalar(d.(flag))&&~d.(flag),id,'Unsupported qualification claim.');
end
objectives=zeros(size(ranks));
assert(numel(d.Candidates)==numel(ranks),id,'Missing searched rank operands.');
for k=1:numel(ranks)
    q=request; q.Rank=ranks(k); pack=sixgr.phy.mimo.CodebookEngine.enumerate(q);
    v=d.Candidates{k}; scores=zeros(size(pack.CandidateIndices));
    assert(isequal(v.CandidateIndices,pack.CandidateIndices)&& ...
        isequal(v.CandidateMatrixSHA256,pack.MatrixSHA256)&& ...
        numel(v.CandidateSumLog2OnePlusSINR)==numel(scores)&& ...
        numel(v.CandidateSINRSHA256)==numel(scores),id,'Candidate support changed.');
    assert(v.CandidateSnapshotCount==size(reception.CSIRSChannelEstimate,1)*size(reception.CSIRSChannelEstimate,2)&& ...
        v.CandidateLayerCount==ranks(k)&&all(strlength(string(v.CandidateSINRSHA256))==64),id,'Original operand dimensions/hash missing.');
    sums=double(v.CandidateSumLog2OnePlusSINR(:));
    assert(all(isfinite(sums))&&all(sums>=0),id,'Invalid retained objective operands.');
    scores=sums/double(v.CandidateSnapshotCount);
    assert(all(abs(scores-v.CandidateMetric(:))<=1e-12*max(1,abs(scores))),id,'Objective arithmetic changed.');
    % The retained producer metric owns exact floating-point tie order.
    [objectives(k),j]=max(v.CandidateMetric);
    assert(v.SelectedIndex==j-1 && v.PMI==pack.CandidateIndices(j)&& ...
        v.SelectedMetric==objectives(k),id,'Candidate arithmetic or first-candidate tie policy changed.');
end
[best,k]=max(objectives); v=d.Candidates{k}; q=request;q.Rank=ranks(k);
W=sixgr.phy.mimo.TypeISinglePanelCodebook.matrix(q,v.PMI);
assert(isequal(objectives,d.ObjectiveByRank)&&d.SelectedRank==ranks(k)&& ...
    d.SelectedObjective==best&&d.SelectedPMI==v.PMI&& ...
    d.SelectedMatrixSHA256==sixgr.phy.mimo.MatrixContract.digest(W),id,'Rank arithmetic/tie selection changed.');
layer=csi.SelectionInfo.SelectedSINRPerRELayer;
assert(isequal(size(layer),[v.CandidateSnapshotCount,ranks(k)])&&all(isfinite(layer(:)))&&all(layer(:)>=0)&& ...
    sixgr.phy.waveform.WaveformHash.runtimeArray(layer)==v.CandidateSINRSHA256(v.SelectedIndex+1), ...
    id,'Selected receiver SINR/hash changed.');
assert(abs(sum(sum(log2(1+layer),2))-v.CandidateSumLog2OnePlusSINR(v.SelectedIndex+1)) ...
    <=1e-12*max(1,v.CandidateSumLog2OnePlusSINR(v.SelectedIndex+1)),id,'Selected objective operands changed.');
effective=10*log10(expm1(mean(log1p(layer),'all')));
if isinf(effective)&&effective<0,cqi=0;
else,cqi=sixgr.link.resolveCQIFromConfiguredThresholds(effective, ...
        double(runtime.PortableCQIModel.ThresholdsDB(:).'),runtime.PortableCQIModel.ComparisonToleranceDB);end
e=d.CQIModelEvidence;
assert(e.CQI==cqi && isequaln(e.EffectiveSINRdB,effective) && ...
    isequal(e.ThresholdsDB,double(runtime.PortableCQIModel.ThresholdsDB))&& ...
    e.ComparisonToleranceDB==runtime.PortableCQIModel.ComparisonToleranceDB && ...
    string(e.ModelID)==string(runtime.PortableCQIModel.ModelID)&& ...
    string(e.AuthoredSource)==string(runtime.PortableCQIModel.Source)&& ...
    string(e.CQITable)==string(runtime.PortableCQIModel.CQITable)&& ...
    string(e.Source)=="explicit_configured_threshold_model"&&~e.CalibrationQualified, ...
    id,'CQI model provenance/operands changed.');
assert(csi.RI==ranks(k)&&csi.PMI==v.PMI&&csi.CQI==cqi&& ...
    csi.CRI==state.ResourceOrdinal&&isequal(csi.Precoder_W,W),id,'Returned CSI tuple/operator changed.');
[~,comp]=sixgr.phy.mimo.TypeISinglePanelCodebook.matrix(q,v.PMI);
[li,~]=sixgr.phy.mimo.selectCSILayerIndicator(layer,cqi);
values=struct('CRI',state.ResourceOrdinal,'RI',ranks(k),'CQI_CW0',cqi, ...
    'PMI',v.PMI,'PMI_I11',comp.PMI_I11,'PMI_I12',comp.PMI_I12,'PMI_I13',comp.PMI_I13,'PMI_I2',comp.PMI_I2,'LI',li);
t=sixgr.phy.mimo.CSIReportConfiguration(q,request.Epoch); typed=t.build(values);
assert(isequal(csi.CSIPart1Bits,typed.Part1Bits)&&isequal(csi.CSIPart2Bits,typed.Part2Bits),id,'Original report wire bits changed.');
assert(string(d.Source)=="original_measured_H_portable_MMSE_candidates"&& ...
    string(d.ObjectiveDefinition)=="mean_snapshots_sum_layers_log2_one_plus_MMSE_SINR"&& ...
    string(d.TiePolicy)=="first_sorted_rank_then_first_candidate",id,'Selection policy claim changed.');
end
