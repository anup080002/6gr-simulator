classdef SharedReceiveOnlyEvidence
    % Lossless completed-receiver evidence, not a manufactured UL trial.
    % Keep active receiver/HARQ state in memory; historical IQ and decoder
    % arrays have an immutable, checksum-bound on-demand archive.
    methods (Static)
        function receipt=write(root,item,result)
            manifest=localManifest(item,result);
            root=sixgr.util.canonicalPath(root);
            assert(strlength(root)>0,'sixgr:truth:ReceiveOnlyArchiveRoot', ...
                'A completed observation requires an explicit run artifact root.');
            relative=localRelative(manifest);
            path=fullfile(root,relative);
            assert(~isfile(path),'sixgr:truth:ReceiveOnlyArchiveExists', ...
                'Never overwrite an existing receive-only evidence archive.');
            sixgr.util.matSave(path,struct('Manifest',manifest,'Item',item,'Result',result), ...
                'UseArtifactStore',false,'ForceV73',true);
            info=dir(path);
            receipt=struct('Schema',"SharedReceiveOnlyEvidence/v1", ...
                'ObservationID',manifest.ObservationID,'GrantContextID',manifest.GrantContextID, ...
                'RootFolder',root,'EvidenceMATFile',relative, ...
                'EvidenceSHA256',string(sixgr.util.sha256File(path)), ...
                'EvidenceBytes',double(info.bytes),'Manifest',manifest, ...
                'Source',"actual_receive_only_capture_and_completed_receiver_lossless_archive");
            % matSave verifies published bytes. Independently reopen the
            % bound header before allowing any in-memory owner to retire.
            sixgr.truth.SharedReceiveOnlyEvidence.read(receipt,"Manifest");
        end

        function value=read(receipt,part)
            assert(isscalar(string(part)) && any(string(part)==["Item","Result","Manifest"]), ...
                'sixgr:truth:ReceiveOnlyArchivePart','Read one explicit archived component.');
            assert(isstruct(receipt) && isscalar(receipt) && all(isfield(receipt, ...
                {'Schema','ObservationID','GrantContextID','RootFolder','EvidenceMATFile', ...
                 'EvidenceSHA256','EvidenceBytes','Manifest'})) && ...
                string(receipt.Schema)=="SharedReceiveOnlyEvidence/v1", ...
                'sixgr:truth:InvalidReceiveOnlyArchive','Require a complete lossless evidence receipt.');
            m=receipt.Manifest;
            assert(string(receipt.ObservationID)==string(m.ObservationID) && ...
                string(receipt.GrantContextID)==string(m.GrantContextID) && ...
                string(receipt.EvidenceMATFile)==localRelative(m), ...
                'sixgr:truth:ReceiveOnlyArchiveIdentity','Do not redirect an observation to another archive.');
            root=sixgr.util.canonicalPath(receipt.RootFolder);
            assert(strlength(root)>0,'sixgr:truth:ReceiveOnlyArchiveRoot','Retain the exact run root.');
            path=fullfile(root,receipt.EvidenceMATFile);
            info=dir(path);
            assert(isscalar(info) && ~info.isdir && info.bytes==receipt.EvidenceBytes, ...
                'sixgr:truth:ReceiveOnlyArchiveMissing','The complete bound evidence file is required.');
            loaded=sixgr.util.loadVerifiedMAT(path,string(receipt.EvidenceSHA256), ...
                unique(["Manifest",string(part)],'stable'));
            assert(isequaln(loaded.Manifest,m),'sixgr:truth:ReceiveOnlyArchiveIdentity', ...
                'Archived observation metadata changed.');
            value=loaded.(part);
            if string(part)=="Item"
                assert(value.Kind=="PUSCHReceiveOnly" && value.ID==m.ObservationID && ...
                    string(value.Context.Grant.PHYGrant.GrantContextId)==m.GrantContextID, ...
                    'sixgr:truth:ReceiveOnlyArchiveIdentity','The loaded capture has another identity.');
                [ids,hashes,sizes,classes]=localPlanes(value);
                assert(isequal(ids,m.PlaneIDs) && isequal(hashes,m.PlaneSHA256) && ...
                    isequal(sizes,m.PlaneSizes) && isequal(classes,m.PlaneClasses), ...
                    'sixgr:truth:ReceiveOnlyArchiveSamples','Capture samples must survive exactly.');
            elseif string(part)=="Result"
                assert(value.ObservationID==m.ObservationID && ...
                    string(value.GrantSnapshot.PHYGrant.GrantContextId)==m.GrantContextID, ...
                    'sixgr:truth:ReceiveOnlyArchiveIdentity','The loaded receiver has another identity.');
                samples=value.Observation.readComplete();
                assert(sixgr.phy.waveform.WaveformHash.numeric(samples)==m.ReceiverObservationSHA256 && ...
                    isequal(size(samples),m.ReceiverObservationSize) && ...
                    string(class(samples))==m.ReceiverObservationClass, ...
                    'sixgr:truth:ReceiveOnlyArchiveSamples','Receiver samples must survive exactly.');
            end
        end
    end
end

function m=localManifest(item,result)
assert(isstruct(item) && isscalar(item) && item.Kind=="PUSCHReceiveOnly" && ...
    item.ID==item.Context.ObservationID && ~isfield(item.Context,'Prepared') && ...
    isstruct(result) && isscalar(result) && result.ObservationID==item.ID && ...
    isequaln(result.GrantSnapshot,item.Context.Grant) && ...
    isequal(result.ULHARQReceiverStateCommitted,true) && ...
    isequal(result.ULHARQSchedulerStateCommitted,true) && ...
    isequal(result.PreparedTransmitterConsumed,false) && ...
    isequal(result.OraclePayloadBitsUsed,false) && isequal(result.TransmittedTBScored,false), ...
    'sixgr:truth:UncommittedReceiveOnlyArchive', ...
    'Archive completed actual reception without inventing UE transmission or discarding active HARQ state.');
[ids,hashes,sizes,classes]=localPlanes(item);
o=result.Observation;
assert(o.isComplete() && result.ReceiverInvokedAtSample>=o.EndSampleExclusive && ...
    all(arrayfun(@(p)p.Observation.StartSample==o.StartSample && ...
        p.Observation.EndSampleExclusive==o.EndSampleExclusive && ...
        p.Observation.SampleRateHz==o.SampleRateHz,item.Planes)), ...
    'sixgr:truth:ReceiveOnlyArchiveClock','Archive exact complete capture boundaries.');
samples=o.readComplete();
m=struct('Schema',"SharedReceiveOnlyEvidence/v1",'ObservationID',string(item.ID), ...
    'GrantContextID',string(item.Context.Grant.PHYGrant.GrantContextId), ...
    'UEIndex',double(item.UE),'StartSample',o.StartSample, ...
    'EndSampleExclusive',o.EndSampleExclusive,'SampleRateHz',o.SampleRateHz, ...
    'ReceiverInvokedAtSample',double(result.ReceiverInvokedAtSample), ...
    'PlaneIDs',ids,'PlaneSHA256',hashes,'PlaneSizes',sizes,'PlaneClasses',classes, ...
    'ReceiverObservationSHA256',sixgr.phy.waveform.WaveformHash.numeric(samples), ...
    'ReceiverObservationSize',size(samples),'ReceiverObservationClass',string(class(samples)), ...
    'UEPUSCHTransmitted',false,'EvidenceScope',"completed_receive_only_not_transmitted_TB_performance");
end

function relative=localRelative(manifest)
key=sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(manifest),'UTF-8')));
relative="air_interface/mat/receive_only_observation_"+string(key)+".mat";
end

function [ids,hashes,sizes,classes]=localPlanes(item)
assert(numel(item.Planes)==2,'sixgr:truth:ReceiveOnlyArchivePlanes','Retain both actual RF observation planes.');
ids=string({item.Planes.ReceiverID});
assert(nnz(endsWith(ids,':pre_rf'))==1 && nnz(endsWith(ids,':post_rf'))==1, ...
    'sixgr:truth:ReceiveOnlyArchivePlanes','No substituted or missing RF plane.');
hashes=strings(1,2); sizes=zeros(2,2); classes=strings(1,2);
for k=1:2
    o=item.Planes(k).Observation;
    assert(o.isComplete(),'sixgr:truth:UncommittedReceiveOnlyArchive','Do not retire partial samples.');
    samples=o.readComplete();
    hashes(k)=sixgr.phy.waveform.WaveformHash.numeric(samples);
    sizes(k,:)=size(samples); classes(k)=string(class(samples));
end
end
