function slot=srsResultDeliverySlot(state,row,producerSlot)
% A measured SRS capture is not available at its producer slot boundary.
slot=double(sixgr.util.structGet(state,'CurrentSlot',NaN));
if nargin>=3, slot=double(producerSlot); end
if isstruct(row) && isscalar(row), row=struct2table(row,'AsArray',true); end
assert(istable(row) && height(row)==1,'sixgr:truth:InvalidSRSDeliveryRow','Supply one typed received result.');
if ismember('Slot',row.Properties.VariableNames), slot=double(row.Slot(end)); end
clocked=ismember('ObservationEndSampleExclusive',row.Properties.VariableNames) && ...
    any(isfinite(row.ObservationEndSampleExclusive));
if ~clocked
    assert(~ismember('RuntimeTransportMode',row.Properties.VariableNames) || ...
        ~any(string(row.RuntimeTransportMode)=="shared_physical_stream_SRS_received_completion"), ...
        'sixgr:truth:MissingSRSObservationClock','Shared SRS cannot omit its actual observation clock.');
    return; % Explicit legacy component/state-machine fixture, not shared RX.
end
required=["ObservationStartSample","ObservationEndSampleExclusive","ObservationSampleRateHz", ...
    "ObservationCompletionTime_s","ObservationCoverageSource", ...
    "ObservationDeliverySlot","ObservationDeliveryTime_s","ObservationDeliverySource"];
assert(height(row)==1 && all(ismember(required,string(row.Properties.VariableNames))), ...
    'sixgr:truth:MissingSRSDeliveryClock','Retain SRS reception and scheduler delivery coordinates.');
fs=row.ObservationSampleRateHz; first=row.ObservationStartSample; stop=row.ObservationEndSampleExclusive;
validateattributes([first stop],{'numeric'},{'real','finite','integer','nonnegative'});
validateattributes(fs,{'numeric'},{'real','scalar','finite','positive'});
now=(state.CurrentSlot-1)*state.SlotDuration_s;
assert(stop>first && row.ObservationCompletionTime_s==stop/fs && stop/fs<=now && ...
    row.ObservationDeliverySlot==state.CurrentSlot && row.ObservationDeliveryTime_s==now && ...
    row.ObservationCoverageSource=="complete_contiguous_received_sample_buffer" && ...
    row.ObservationDeliverySource=="canonical_slot_start_after_complete_received_window", ...
    'sixgr:truth:SRSResultBeforeDelivery','No SRS consumer may use incomplete or undelivered samples.');
slot=double(state.CurrentSlot);
end
