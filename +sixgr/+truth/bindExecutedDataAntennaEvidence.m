function row = bindExecutedDataAntennaEvidence(row, phyGrant, mapping, projection, originalInput)
%BINDEXECUTEDDATAANTENNAEVIDENCE Keep layers, ports and elements distinct.
% Bind only after the shared data TX/RX identity check, using the mapping and
% projection retained by that transmission's queueData context. Never rebuild
% the array from today's YAML, or infer logical ports from layers/DM-RS ports.
% TS 38.211 4.4.1 defines antenna ports; 6.3.1.3 and 7.3.1.3 define layers.
% The logical-to-element/RF-chain architecture is a simulator/hardware model,
% not a mandated NR physical-element layout. This binder does not alter IQ.
arguments
    row table
    phyGrant (1,1) struct
    mapping (1,1) struct
    projection {mustBeNumeric}
    originalInput {mustBeNumeric} = []
end
id = 'sixgr:truth:ExecutedDataAntennaEvidenceMismatch';
assert(height(row)==1,id,'Bind one completed data transmission, not a multi-grant table.');
contract = sixgr.phy.grant.assertPHYGrantDimensions(phyGrant, ...
    'completed_shared_data_antenna_evidence');
grantID = localText(phyGrant,'GrantContextId',id);
assert(localText(mapping,'ContractVersion',id)=="SharedDataWaveformElementMapping/v1", ...
    id,'An actual supported waveform-mapping receipt is required.');
domain = localText(mapping,'InputWaveformDomain',id);
assert(any(domain==["element","logical_port"]) && domain==string(contract.WaveformDomain), ...
    id,'The executed waveform domain must match the frozen PHY grant.');
elementDomain = domain=="element";
assert(localBoolean(mapping,'ElementDomainPrecodingAppliedBeforeSharedStream',id)==elementDomain && ...
    localBoolean(mapping,'AdditionalProjectionApplied',id)==~elementDomain, ...
    id,'Element-domain precoding must not be applied twice by the shared stream.');
expectedSource = "configured_logical_port_to_physical_element_projection";
if elementDomain
    expectedSource = "frozen_element_domain_waveform_identity_stream_projection";
end
assert(localText(mapping,'Source',id)==expectedSource,id, ...
    'The mapping source must describe the operation actually executed.');
for pair = ["InputWaveformColumns","NumWaveformColumns"; ...
        "NumLogicalPorts","NumLogicalPorts"; ...
        "NumPhysicalElements","NumElements"; ...
        "ProjectionRows","NumElements"; ...
        "ProjectionColumns","NumWaveformColumns"].'
    assert(localCount(mapping,pair(1),id)==contract.(pair(2)),id, ...
        'Executed mapping %s disagrees with frozen %s.',pair(1),pair(2));
end
assert(ismatrix(projection) && ...
    isequal(size(projection),[contract.NumElements contract.NumWaveformColumns]) && ...
    all(isfinite(projection),'all'),id,'The exact retained projection has invalid dimensions/values.');
projectionHash = sixgr.phy.mimo.MatrixContract.digest(double(projection));
assert(localText(mapping,'ProjectionSHA256',id)==string(projectionHash),id, ...
    'The retained mapping matrix differs from the executed projection receipt.');
if elementDomain
    assert(isequal(projection,eye(contract.NumElements,'like',projection)),id, ...
        'Element-domain IQ must use identity stream projection, not a second beamformer.');
else
    residual = norm(double(projection'*projection)-eye(contract.NumLogicalPorts),'fro');
    assert(residual<=1e-9*contract.NumLogicalPorts,id, ...
        'The logical-port projection must retain the mapper power-preservation contract.');
end

% Check present aliases rather than silently relabelling conflicting rows.
% Missing values may be bound only from this exact executed mapping context.
row = localBind(row,'Direction',string(contract.Direction),id);
for name = ["NumLayers","Layers"]
    if ismember(name,string(row.Properties.VariableNames))
        row = localBind(row,name,contract.NumLayers,id);
    end
end
% Reuse the primary trial's existing identity vocabulary. A second apparent
% identity column must not hide a contradiction with the original producer.
row = localBind(row,'FrozenGrantContextId',grantID,id);
for name = ["GrantContextId","PHYGrantContextId"]
    if ismember(name,string(row.Properties.VariableNames))
        row = localBind(row,name,grantID,id);
    end
end
row = localBind(row,'NumLogicalPorts',contract.NumLogicalPorts,id);
row = localBind(row,'PrecodingNumLogicalPorts',contract.NumLogicalPorts,id);
row = localBind(row,'NumPhysicalElements',contract.NumElements,id);
for pair = ["PhysicalTxAntennas","NumElements"; ...
        "PrecodingNumPorts","NumWaveformColumns"; ...
        "PrecodingNumLayers","NumLayers"].'
    if ismember(pair(1),string(row.Properties.VariableNames))
        row = localBind(row,pair(1),contract.(pair(2)),id);
    end
end
row = localBind(row,'DataWaveformNumColumns',contract.NumWaveformColumns,id);
row = localBind(row,'DataWaveformDomain',domain,id);
row = localBind(row,'FrozenDataLayers',contract.NumLayers,id);
row = localBind(row,'FrozenDataDMRSPortCount',numel(phyGrant.CodingLayout.DMRSPortSet),id);
row = localBind(row,'FrozenDataDMRSPortSetJSON', ...
    string(jsonencode(double(phyGrant.CodingLayout.DMRSPortSet(:).'))),id);
% RF-chain count is declared in the frozen architecture, not measured from
% waveform columns. Do not overwrite independently measured RF execution.
row = localBind(row,'FrozenNumRFChains', ...
    localCount(phyGrant.AntennaArchitecture,'NumRFChains',id),id);
row = localBind(row,'SharedStreamProjectionRows',size(projection,1),id);
row = localBind(row,'SharedStreamProjectionColumns',size(projection,2),id);
row = localBind(row,'SharedStreamProjectionSHA256',string(projectionHash),id);
row = localBind(row,'SharedStreamAdditionalProjectionApplied',~elementDomain,id);
row = localBind(row,'DataAntennaMappingSource',expectedSource,id);
row = localBind(row,'DataAntennaEvidenceSource', ...
    "frozen_PHYGrant_and_same_transmission_executed_element_mapping",id);
if isfield(mapping,'SpatialMappingPower')
    p=mapping.SpatialMappingPower;
    required=["Contract","MatrixSHA256","InputColumns","OutputColumns", ...
        "InputSecondMoment","OutputSecondMoment","ExpectedOutputSecondMoment", ...
        "SampleCount","RadiatedPowerClaimed","InputPrecision","OutputPrecision", ...
        "MatrixPrecision","InputArraySHA256","OutputArraySHA256","Population", ...
        "ReferencePlane","Source","NumericalTolerance","CovarianceResidual", ...
        "InputMeanSquare","OutputMeanSquare","ExpectedOutputMeanSquare"];
    assert(isstruct(p) && isscalar(p) && ...
        all(isfield(p,required)) && ...
        string(p.Contract)=="executed_spatial_mapping_power/v1" && ...
        string(p.MatrixSHA256)==string(projectionHash) && ...
        p.InputColumns==size(projection,2) && p.OutputColumns==size(projection,1) && ...
        isequal(size(p.InputSecondMoment),[p.InputColumns p.InputColumns]) && ...
        isequal(size(p.OutputSecondMoment),[p.OutputColumns p.OutputColumns]) && ...
        p.SampleCount>0 && p.SampleCount==fix(p.SampleCount) && ...
        ~p.RadiatedPowerClaimed,id,'Spatial power receipt must belong to this executed map.');
    assert(~isempty(originalInput) && isfloat(originalInput) && ismatrix(originalInput) && ...
        size(originalInput,1)==p.SampleCount && size(originalInput,2)==p.InputColumns && ...
        string(p.InputPrecision)==string(class(originalInput)) && ...
        string(p.MatrixPrecision)==string(class(projection)) && ...
        any(string(p.OutputPrecision)==["single","double"]) && ...
        string(p.InputArraySHA256)==sixgr.phy.waveform.WaveformHash.runtimeArray(originalInput), ...
        id,'Power evidence must identify the original prepared waveform, not a same-covariance substitute.');
    assert(localText(p,'Population',id)=="same_samples_including_cp_and_idle_no_mean_subtraction" && ...
        localText(p,'ReferencePlane',id)=="digital_spatial_map_before_shared_TX_RF" && ...
        localText(p,'Source',id)=="actual_input_and_mapped_output_samples",id, ...
        'Power evidence has a conflicting population, plane or producer.');
    precision=eps('double');
    if any([string(p.InputPrecision),string(p.OutputPrecision),string(p.MatrixPrecision)]=="single")
        precision=double(eps('single'));
    end
    predicted=double(projection)*p.InputSecondMoment*double(projection)';
    residual=norm(p.OutputSecondMoment-predicted,'fro');
    tolerance=128*precision*max([1 size(projection)])* ...
        max(norm(predicted,'fro'),norm(p.OutputSecondMoment,'fro'));
    assert(isscalar(p.NumericalTolerance) && isfinite(p.NumericalTolerance) && ...
        p.NumericalTolerance==tolerance && isfinite(residual) && residual<=tolerance && ...
        abs(residual-p.CovarianceResidual)<=eps(max(1,residual))*16 && ...
        isequaln(predicted,p.ExpectedOutputSecondMoment) && ...
        p.InputMeanSquare==real(trace(p.InputSecondMoment)) && ...
        p.OutputMeanSquare==real(trace(p.OutputSecondMoment)) && ...
        p.ExpectedOutputMeanSquare==real(trace(predicted)),id, ...
        'Retained power matrices and their arithmetic disagree.');
    for name=["SampleCount","InputColumns","OutputColumns","InputMeanSquare", ...
            "OutputMeanSquare","ExpectedOutputMeanSquare","CovarianceResidual", ...
            "NumericalTolerance","InputArraySHA256","OutputArraySHA256", ...
            "InputPrecision","OutputPrecision","MatrixPrecision","Population","ReferencePlane","Source"]
        row=localBind(row,"DataMapping"+name,p.(name),id);
    end
    for name=["InputSecondMoment","OutputSecondMoment","ExpectedOutputSecondMoment"]
        row=localBind(row,"DataMapping"+name+"Array", ...
            sixgr.runtime.RawCSVArrayCodec.encode(p.(name)),id);
    end
end
end

function value = localText(data,name,id)
assert(isfield(data,name),id,'Required mapping field %s is absent.',name);
raw = data.(name);
assert(isstring(raw) || (ischar(raw) && isrow(raw)),id, ...
    'Mapping field %s must be scalar text.',name);
value = string(raw);
assert(isscalar(value) && ~ismissing(value) && strlength(value)>0,id, ...
    'Mapping field %s must be populated scalar text.',name);
end

function value = localCount(data,name,id)
assert(isfield(data,name),id,'Required dimension %s is absent.',name);
value = data.(name);
assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && value>=1 && value==fix(value),id, ...
    'Dimension %s must be a positive integer.',name);
value = double(value);
end

function value = localBoolean(data,name,id)
assert(isfield(data,name),id,'Required application flag %s is absent.',name);
value = data.(name);
assert((islogical(value) || isnumeric(value)) && isreal(value) && ...
    isscalar(value) && isfinite(value) && any(value==[0 1]),id, ...
    'Application flag %s must be an explicit boolean.',name);
value = logical(value);
end

function row = localBind(row,name,value,id)
if ismember(string(name),string(row.Properties.VariableNames))
    old = row.(name);
    if isstring(value)
        assert(isstring(old) || iscellstr(old) || ischar(old),id, ...
            'Existing %s must use a text representation.',name);
        old = string(old);
        assert(isscalar(old) && (ismissing(old) || strlength(old)==0 || old==value), ...
            id,'Existing %s contradicts this transmission.',name);
    else
        assert((isnumeric(old) || islogical(old)) && isreal(old) && ...
            isscalar(old) && (isnan(old) || old==value),id, ...
            'Existing %s contradicts this transmission.',name);
    end
end
row.(name) = value;
end
