function [cfgTX,ra,policy]=buildCellRARTransmissionContext(cfg,calendar,receipt,slotAvailable,selectedRAPIDs)
% Original cell common configuration + completed PRACH -> RAR TX context.
% No UE ordinal/checkpoint, selected TX preamble or decoded UE state is used.
% This is a scheduling proposal. It does not allocate identities or execute RF.
if nargin<4, slotAvailable=@(~,~)true; end % No prior reservations in a standalone context.
assert(isa(slotAvailable,'function_handle'),'sixgr:truth:CellRARResourcePolicy', ...
    'Pass the original cell reservation predicate.');
assert(calendar.ContractVersion=="cell_PRACH_receive_calendar/v1" && ...
    calendar.SHA256==localHash(rmfield(calendar,'SHA256')) && ...
    receipt.ContractVersion=="completed_cell_PRACH_receiver/v1" && ...
    receipt.SHA256==localHash(rmfield(receipt,'SHA256')) && ...
    receipt.CellCalendarSHA256==calendar.SHA256 && receipt.ReceiverExecuted && ...
    receipt.ServingCell==calendar.CellID && receipt.PhysicalCellID==calendar.PhysicalCellID, ...
    'sixgr:truth:CellRAROriginalReceiverRequired','Retain the original completed cell receive contract.');
assert(~isempty(receipt.AdmittedDetections),'sixgr:truth:CellRARNoAdmittedDetection', ...
    'No RAR context is created from an empty admitted receiver population.');
assert(isempty(fieldnames(sixgr.util.structGet(cfg,'UECommonCellConfiguration',struct()))) && ...
    isempty(fieldnames(sixgr.util.structGet(cfg,'UECommonMIBConfiguration',struct()))), ...
    'sixgr:truth:CellRARUEAuthorityForbidden','The gNB producer cannot use a UE installation.');
assert(isequaln(sixgr.rrc.asn1.buildBCCHDLSCHMessage(cfg),calendar.ConfiguredSIB1Tree), ...
    'sixgr:truth:CellRARConfigurationChanged','Use the same common configuration that armed PRACH reception.');
d=receipt.AdmittedDetections;
if nargin>=5
    validateattributes(selectedRAPIDs,{'numeric'},{'vector','nonempty','real','finite','integer','>=',0,'<=',63});
    assert(numel(unique(selectedRAPIDs))==numel(selectedRAPIDs) && ...
        all(ismember(selectedRAPIDs,[d.DetectedPreambleIndex])), ...
        'sixgr:truth:CellRARUnobservedSelection','Only actual admitted RAPIDs may enter the cell response.');
    d=d(ismember([d.DetectedPreambleIndex],selectedRAPIDs));
end
beams=unique([d.AssociatedSSBIndex0]);
assert(isscalar(beams),'sixgr:truth:CellRARMultipleBeamResponseUnsupported', ...
    'Distinct SSB-associated receiver groups require separately scheduled beam responses, not a guessed UE beam.');
cfgTX=cfg;
cfgTX.random_access.associated_ssb_index=beams;
cfgTX.random_access.associated_ssb_selection_source="original_cell_RO_CB_preamble_partition";
cfgTX.phy.ssb.runtimeSSBIndex=beams;
carrier=sixgr.phy.grid.makeCarrier(cfgTX);
serving=calendar.ConfiguredSIB1Tree.message.c1.systemInformationBlockType1.servingCellConfigCommon;
dl=serving.downlinkConfigCommon.initialDownlinkBWP;
[start,nrb]=sixgr.bwop.RIVFDRA.decode(275,dl.genericParameters.locationAndBandwidth);
cp="normal"; if isfield(dl.genericParameters,'cyclicPrefix'), cp=string(dl.genericParameters.cyclicPrefix); end
bwp=struct('StartRB',start,'SizeRB',nrb, ...
    'SubcarrierSpacing_kHz',str2double(erase(string(dl.genericParameters.subcarrierSpacing),"kHz")), ...
    'CyclicPrefix',cp);
common=struct('ConfigurationSource',"original_gNB_common_configuration", ...
    'InitialDLBWP',bwp,'PDCCHConfigCommonPresent',isfield(dl,'pdcch_ConfigCommon'), ...
    'PDCCHConfigCommon',struct(),'PDSCHConfigCommon',struct());
if common.PDCCHConfigCommonPresent, common.PDCCHConfigCommon=dl.pdcch_ConfigCommon; end
if isfield(dl,'pdsch_ConfigCommon'), common.PDSCHConfigCommon=dl.pdsch_ConfigCommon; end
ul=serving.uplinkConfigCommon.initialUplinkBWP;
[ulStart,ulSize]=sixgr.bwop.RIVFDRA.decode(275,ul.genericParameters.locationAndBandwidth);
ulCP="normal";if isfield(ul.genericParameters,'cyclicPrefix'),ulCP=string(ul.genericParameters.cyclicPrefix);end
common.InitialULBWP=struct('StartRB',ulStart,'SizeRB',ulSize, ...
    'SubcarrierSpacing_kHz',str2double(erase(string(ul.genericParameters.subcarrierSpacing),"kHz")), ...
    'CyclicPrefix',ulCP);
common.PUSCHConfigCommonPresent=isfield(ul,'pusch_ConfigCommon');
common.PUSCHConfigCommon=sixgr.util.structGet(ul,'pusch_ConfigCommon',struct());
common.CellCalendarSHA256=calendar.SHA256;
cfgTX.GNBCommonCellConfiguration=common;
% The gNB uses its transmitted MIB fields. Resolving their Type0 geometry
% does not mean that any UE decoded those fields.
mib=sixgr.phy.broadcast.splitPDCCHConfigSIB1(cfgTX.phy.mib.pdcchConfigSIB1, ...
    'Source',"original_gNB_configured_MIB");
mib.DMRSTypeAPosition=cfgTX.phy.mib.dmrsTypeAPosition;
type0=sixgr.phy.broadcast.deriveType0PDCCHFromMIB(carrier,cfgTX,mib);
cfgTX.GNBCommonMIBConfiguration=struct('Source',"original_gNB_configured_MIB", ...
    'CORESET0Present',true,'CORESET0NumRB',type0.CORESET0.NumRB, ...
    'CORESET0RBStart',type0.CORESET0.RBStart,'DMRSTypeAPosition',mib.DMRSTypeAPosition);
node=cfg.random_access;
msg2=localAllocation(node.msg2_pdsch,false);
msg2.TBScaling=sixgr.util.structGet(node,'msg2_pdsch.tb_scaling',0);
msg3=localAllocation(node.msg3_pusch,true);
assert(~msg3.EnablePTRS,'sixgr:truth:CellRARMsg3PTRSUnsupported', ...
    'RAR Msg3 cannot inherit dedicated PUSCH PT-RS.');
policy=struct('NSizeGrid',carrier.NSizeGrid,'CarrierSCSkHz',carrier.SubcarrierSpacing, ...
    'CarrierCyclicPrefix',string(carrier.CyclicPrefix),'RARGrantConfig', ...
    localProject(node.rar_grant,["field_layout","frequency_hopping","time_resource_assignment","tpc_command"]), ...
    'Msg3PUSCH',localProject(msg3,["PRBStart","NumPRB","SymbolStart","NumSymbols", ...
    "MCS","Modulation","TargetCodeRate","NLayers","RV","MCSTable","TransformPrecoding","EnablePTRS"]));
policy.PUSCHCommonContext=sixgr.mac.ra.resolveRARCommonPUSCHContext(cfgTX);
grant=sixgr.mac.ra.buildRARULGrant(policy); a=grant.TimeDomainAllocation;
assert(node.timing.msg3_k2_slots==a.K2,'sixgr:phy:ia:RARConfiguredK2Mismatch', ...
    'Configured Msg3 K2 must match the actual encoded RAR TDRA.');
frame=sixgr.phy.FrameStructureEngine(cfgTX,'FrameCoreOnly',true);
[~,control]=sixgr.phy.ra.resolveRARCommonControl(cfgTX,carrier);
p=receipt.Plan; fs=p.SampleRateHz;
tc=double(sixgr.phy.frame.AbsoluteTime.TicksPerSecond)/fs;
assert(tc==fix(tc) && p.CellCalendarSHA256==calendar.SHA256 && ...
    receipt.CompletedAtSample==p.ReceiveEndSampleExclusive, ...
    'sixgr:truth:CellRARClockMismatch','Require the original complete receiver clock.');
% The cell predicts opportunities from its RO clock. The independent UE
% window still uses the UE's own emitted end/received clock; no UE expiry is
% overwritten if propagation or decoding prevents reception.
nativeEnd=p.NativeActiveEndTicksExclusive-p.CommonOffset.NTAOffset_Tc;
window=sixgr.phy.ia.RARMonitoringWindow.resolve(frame,control,nativeEnd,node.ra_response_window_slots);
t=sixgr.phy.frame.AbsoluteTime.fromTicks(nativeEnd-int64(1));
[f,s,~,~]=t.toNumerology(frame.Numerology);
% Classify the final occupied native tick into its containing slot. It is
% generally not an OFDM symbol boundary. Do not round the receive clock;
% candidate TX starts below are compared with the exact completed sample.
endSlot=double(f)*carrier.SlotsPerFrame+double(s);
delay=node.timing.rar_processing_delay_slots;
validateattributes(delay,{'numeric'},{'scalar','real','integer','positive','finite'});
first=endSlot+delay;
resources=sixgr.phy.frame.CommonDLResourcePlan(cfgTX); resources.validateSIB1References();
msg2Slot=NaN; msg3Slot=NaN;
rejected=struct('Slot0',{},'Reason',{});
for candidate=reshape(window.MonitoringSlots,1,[])
    if candidate<first, continue; end
    startSample=sixgr.phy.frame.slotStartSample(carrier,candidate,fs);
    if startSample<receipt.CompletedAtSample, continue; end
    ulSlot=candidate+a.K2+a.Msg3AdditionalDelaySlots;
    if ~frame.IsDLAllocation(candidate,[msg2.SymbolStart msg2.NumSymbols]) || ...
            ~frame.IsULAllocation(ulSlot,[a.StartSymbol a.NumSymbols]), continue; end
    stop=sixgr.phy.frame.AbsoluteTime.fromAbsoluteSlotSymbol(candidate,msg2.SymbolStart,frame.Numerology);
    stop=stop.plusSymbols(msg2.NumSymbols,frame.Numerology);
    if stop.Ticks>window.ExpiryTicksExclusive, continue; end
    [available,~]=resources.checkPDSCH(msg2,candidate);
    if ~available
        rejected(end+1)=struct('Slot0',candidate,'Reason',"configured_common_DL_overlap"); %#ok<AGROW>
        continue;
    end
    if ~slotAvailable(candidate,ulSlot)
        rejected(end+1)=struct('Slot0',candidate,'Reason',"prior_cell_access_slot_reservation"); %#ok<AGROW>
        continue;
    end
    msg2Slot=candidate; msg3Slot=ulSlot; break;
end
ra=struct('ContractVersion',"cell_received_RAR_transmission_context/v1", ...
    'Source',"original_cell_common_configuration_and_completed_PRACH", ...
    'ServingCell',calendar.CellID,'CellId',calendar.PhysicalCellID,'NCellID',carrier.NCellID, ...
    'UEId',0,'StrictMode',logical(cfg.run.strictMode), ...
    'NStartGrid',carrier.NStartGrid,'NSizeGrid',carrier.NSizeGrid, ...
    'CarrierSCSkHz',carrier.SubcarrierSpacing,'CarrierCyclicPrefix',string(carrier.CyclicPrefix), ...
    'RARNTI',p.ExpectedRARNTI,'PRACHAbsoluteSlot',d(1).PRACHAbsoluteSlot, ...
    'PRACHOccasionSymbol',d(1).PRACHOccasionSymbol,'PRACHFrequencyIndex',d(1).PRACHFrequencyIndex, ...
    'Msg2Slot',msg2Slot,'Msg3Slot',msg3Slot,'Msg2PDSCH',msg2,'Msg3PUSCH',msg3, ...
    'PUSCHCommonContext',policy.PUSCHCommonContext, ...
    'RARGrantConfig',policy.RARGrantConfig,'ConfiguredCellResponseWindow',window, ...
    'ReceiverCompletedAtSample',receipt.CompletedAtSample,'ReceiverReceiptSHA256',receipt.SHA256, ...
    'CellCalendarSHA256',calendar.SHA256,'AssociatedSSBIndex0',beams, ...
    'SelectedRAPIDs',reshape([d.DetectedPreambleIndex],[],1), ...
    'RejectedResourceCandidates',rejected,'ResponseSchedulable',isfinite(msg2Slot), ...
    'Scope',"cell_response_proposal_not_transmitted_or_UE_received_RAR");
ra.RARDCIReference=sixgr.phy.ra.resolveRARDCIReference(cfgTX);
context=sixgr.phy.pdcch.RARDCIContext.create(ra.RARDCIReference,ra.RARNTI);
schema=sixgr.phy.pdcch.DCISchemaEngine.resolve(context); ra.Msg2DCIPayloadBits=schema.RawBits;
if ra.ResponseSchedulable, sixgr.phy.ra.scheduleMsg2RAR(ra); end
ra.ContextSHA256=localHash(ra);
end

function s=localAllocation(n,isUL)
required=["prb_start","num_prb","symbol_start","num_symbols","modulation","target_code_rate"];
assert(isstruct(n) && isscalar(n) && all(isfield(n,required)), ...
    'sixgr:truth:CellRARGrantPolicyRequired','Retain explicit cell grant geometry and coding policy.');
s=struct('PRBStart',n.prb_start,'NumPRB',n.num_prb,'SymbolStart',n.symbol_start, ...
    'NumSymbols',n.num_symbols,'MCS',sixgr.util.structGet(n,'mcs',0), ...
    'Modulation',string(n.modulation),'TargetCodeRate',n.target_code_rate, ...
    'NLayers',sixgr.util.structGet(n,'n_layers',1),'RV',sixgr.util.structGet(n,'rv',0), ...
    'MCSTable',string(sixgr.util.structGet(n,'mcs_table',"qam64")), ...
    'TransformPrecoding',false,'EnablePTRS',logical(sixgr.util.structGet(n,'ptrs_enabled',false)));
if isUL, s.TransformPrecoding=logical(sixgr.util.structGet(n,'transform_precoding',false)); end
end
function v=localProject(s,names)
assert(all(isfield(s,names)),'sixgr:truth:CellRARGrantPolicyRequired','Missing original cell policy field.');
v=struct(); for name=names, v.(name)=s.(name); end
end
function h=localHash(value)
h=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(value))));
end
