function next=appendPUSCHHARQDecisionAudit(previous,rx,context,observation,availableAtSample)
% One receiver-field audit per completed scheduled PUSCH HARQ occasion.
% Not a per-bit trial, successful transmission, TB result or presence test.
assert(istable(previous),'sixgr:truth:InvalidPUSCHHARQAudit','Prior audit must be a table.');
actual=sixgr.truth.normalizeReceivedPUSCHHARQ(rx,context);
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && ...
    isscalar(observation) && observation.isComplete(), ...
    'sixgr:truth:IncompletePUSCHHARQAuditObservation','Audit requires a complete received observation.');
validateattributes(availableAtSample,{'numeric'},{'scalar','real','finite','integer','>=',observation.EndSampleExclusive});
window=struct('AssignmentDigest',context.Data.AssignmentDigest, ...
    'StartSample',observation.StartSample,'EndSampleExclusive',observation.EndSampleExclusive, ...
    'SampleRateHz',observation.SampleRateHz,'NumReceiveAntennas',observation.NumReceiveAntennas);
id="PUSCH-UCI-"+sixgr.phy.pucch.PUCCHUtil.hash(window);
assert(context.Data.ObservationID==id,'sixgr:truth:PUSCHHARQAuditObservationMismatch', ...
    'Receiver context and actual observation clock/assignment must match before publication.');
next=previous;
count=actual.InformationBitCount;
if count==0, return; end % No manufactured feedback row for empty UCI.
if ~isempty(previous)
    assert(ismember('ObservationID',previous.Properties.VariableNames) && ...
        ~any(previous.ObservationID==id),'sixgr:truth:DuplicatePUSCHHARQDecisionAudit', ...
        'One completed receive window cannot publish its HARQ field twice.');
end
row=struct('ObservationID',id,'ReceiverContextDigest',context.Digest, ...
    'AssignmentDigest',context.Data.AssignmentDigest,'HARQMappingDigest',context.Data.HARQMappingDigest, ...
    'ConfigurationEpoch',context.Data.ConfigurationEpoch, ...
    'ObservationStartSample',observation.StartSample,'ObservationEndSampleExclusive',observation.EndSampleExclusive, ...
    'AvailableAtSample',double(availableAtSample),'SampleRateHz',observation.SampleRateHz, ...
    'Field',"HARQACK",'InformationBitCount',count, ...
    'DecodedBitsJSON',string(jsonencode(double(actual.DecodedBits(:).'))), ...
    'DecodeAttempted',actual.DecodeAttempted,'DecoderWordUsable',NaN, ...
    'ReceiverUsable',actual.DecodeOk,'ReceiverErasure',actual.DTXFlag, ...
    'CRCApplicable',count>=12,'CRCPass',NaN, ...
    'ShortConfidenceApplicable',count<12,'ShortConfidenceAttempted',false, ...
    'ConfidenceAlgorithm',"",'ConfidencePolicySource',"",'ConfidenceModel',"", ...
    'MinimumPosterior',NaN,'SelectedPosterior',NaN,'MaximumPosterior',NaN, ...
    'UniqueMaximum',NaN,'DecoderMatchesMaximum',NaN,'ConfidenceAccepted',NaN, ...
    'DecisionReason',"not_decoded_strict_noise_gate", ...
    'EvidenceSource',actual.Source, ...
    'EvidenceScope',"receiver_field_decision_not_signal_presence_qualification");
if actual.DecodeAttempted
    e=rx.UCIReceiverEvidence.HARQACK;
    assert(isfield(e,'DecoderWordUsable') && islogical(e.DecoderWordUsable) && isscalar(e.DecoderWordUsable), ...
        'sixgr:truth:InvalidPUSCHHARQAudit','Retain raw decoder-word usability separately from final acceptance.');
    row.DecoderWordUsable=double(e.DecoderWordUsable);
    row.CRCPass=e.CRCPass;
    if count<12
        c=e.ShortConfidence; % Validated against bits by normalizeReceivedPUSCHHARQ.
        row.ShortConfidenceAttempted=true;
        row.ConfidenceAlgorithm=c.Algorithm; row.ConfidencePolicySource=c.PolicySource;
        row.ConfidenceModel=c.Model; row.MinimumPosterior=c.MinimumPosterior;
        row.SelectedPosterior=c.SelectedPosterior; row.MaximumPosterior=c.MaximumPosterior;
        row.UniqueMaximum=double(c.UniqueMaximum);
        row.DecoderMatchesMaximum=double(c.DecoderMatchesMaximum);
        row.ConfidenceAccepted=double(c.Accepted); row.DecisionReason=string(c.Reason);
    elseif e.CRCPass==1
        row.DecisionReason="crc_pass";
    else
        row.DecisionReason="crc_failure";
    end
end
next=[previous;struct2table(row,'AsArray',true)];
end
