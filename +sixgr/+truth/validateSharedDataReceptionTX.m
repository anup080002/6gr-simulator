function validateSharedDataReceptionTX(state,harqOut,grant,bits,ue,direction,slot)
% A received shared-stream trial must join its already committed TX once.
id=string(sixgr.util.structGet(harqOut,'SharedTransmissionID',''));
received=sixgr.util.structGet(state,'SharedDataRXCommittedIDs',strings(0,1));
received=[received;sixgr.util.structGet(state, ...
    'SharedDataNoDecodeCommittedIDs',strings(0,1))];
assert(~any(received==id), ...
    'sixgr:truth:DuplicateSharedDataRXCommit','One received attempt cannot update HARQ/CSI/statistics twice.');
ledger=sixgr.util.structGet(state,'SharedDataTXLedger',{});
hit=find(cellfun(@(r)r.Identity.TransmissionID==id,ledger));
assert(isscalar(id) && strlength(id)>0 && isscalar(hit), ...
    'sixgr:truth:SharedDataRXWithoutTXCommit','A shared RX result requires its actual once-committed transmission.');
tx=ledger{hit};
assert(tx.Identity.UEIndex==ue && tx.Identity.Direction==string(direction) && ...
    tx.Identity.RNTI==grant.RNTI && tx.Grant.Slot==slot && ...
    tx.Identity.PHYGrantContextId==string(grant.PHYGrant.GrantContextId) && ...
    isequal(tx.TransportBlockBits,int8(bits(:))) && ...
    tx.Grant.HARQ.HarqID==grant.HARQ.HarqID && ...
    tx.Grant.HARQ.NDI==grant.HARQ.NDI && tx.Grant.HARQ.RV==grant.HARQ.RV, ...
    'sixgr:truth:SharedDataRXTXBindingMismatch', ...
    'Receiver evidence cannot change the transmitted payload, grant, HARQ attempt or UE identity.');
end
