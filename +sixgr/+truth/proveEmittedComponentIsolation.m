function proof=proveEmittedComponentIsolation(trace,request)
%PROVEEMITTEDCOMPONENTISOLATION Finite original-sample dependency, not a replay.
% Receipts are supplied by the original physical/event owners after success.
% This pure checker does not grant authority to externally authored receipts.
% It checks each actual receiver FFT window against original component runs,
% installed TX RF signal memory/delay, and the executed channel FIR/reset
% history. Earlier unrelated signals outside this finite cone are permitted.
id='sixgr:truth:EmittedComponentIsolationEvidence';
required={'TransmitterID','ReceiverID','LinkID','ComponentID','ComponentSHA256', ...
    'SampleRateHz','ConfigurationEpoch','FFTIntervals'};
assert(isstruct(request)&&isscalar(request)&&all(isfield(request,required)),id, ...
    'Use the original component, link, clock and actual measurement FFT support.');
for name=string(required(1:5))
    value=string(request.(name));
    assert(isscalar(value)&&~ismissing(value)&&strlength(value)>0,id,'Missing original identity.');
end
validateattributes(request.SampleRateHz,{'numeric'},{'scalar','real','finite','positive'});
validateattributes(request.ConfigurationEpoch,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
fftWindows=localIntervals(request.FFTIntervals,id);
assert(~isempty(fftWindows)&&iscell(trace)&&~isempty(trace),id,'Retain FFT windows and successful execution history.');
history=zeros(numel(trace),2);
for k=1:numel(trace)
    s=trace{k}; e=s.Execution;
    assert(s.StartSample==e.StartSample&&s.EndSampleExclusive==e.EndSampleExclusive&& ...
        e.SampleRateHz==request.SampleRateHz&&e.ConfigurationEpoch==request.ConfigurationEpoch&& ...
        string(e.Source)=="composed_tx_retained_rf_per_link_channel_sum_receiver_noise_rf"&& ...
        string(e.ApproximationMode)=="none",id,'Only original same-clock successful execution is admissible.');
    history(k,:)=[e.StartSample e.EndSampleExclusive];
end
localIntervals(history,id);
assert(all(history(2:end,1)==history(1:end-1,2)),id,'Execution history has a gap or duplicate interval.');
cones=zeros(0,2); operators=cell(0,1); contributors=cell(0,1);
targetWindows=false(size(fftWindows,1),1); contamination=struct('ComponentID',{},'Intervals',{});
for f=1:size(fftWindows,1)
    window=fftWindows(f,:); localCoverage(history,window,id);
    hit=find(history(:,1)<window(2)&history(:,2)>window(1));
    for k=hit.'
        e=trace{k}.Execution; piece=[max(window(1),history(k,1)) min(window(2),history(k,2))];
        links=e.Links; j=find(string({links.ID})==string(request.LinkID));
        assert(isscalar(j)&&string(links(j).TX)==string(request.TransmitterID)&& ...
            string(links(j).RX)==string(request.ReceiverID),id, ...
            'The actual desired link must point at the requested endpoint throughout each FFT window.');
        d=links(j).Replay.ChannelSignalDependency;
        localReceipt(d,e,"sixgr.channel.executed_signal_dependency/v1",id);
        assert(d.ZeroInputHistoryAtOrigin&&d.InputHistoryStartSample<=piece(1)&& ...
            any(string(d.HistoryInitializationSource)== ...
            ["original_fresh_zero_warmup","original_native_direction_swap_filter_reset", ...
             "original_memoryless_direction_change"])&& ...
            strlength(string(d.FilterSHA256))>0&&strlength(string(d.NativeInitializationSHA256))>0,id, ...
            'Require original initialized/reset native filter authority, not an elapsed-time memory assumption.');
        validateattributes(d.MemorySamples,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
        channelInput=[max(piece(1)-d.MemorySamples,d.InputHistoryStartSample) piece(2)];
        localCoverage(history,channelInput,id);
        rfHit=find(history(:,1)<channelInput(2)&history(:,2)>channelInput(1));
        for r=rfHit.'
            er=trace{r}.Execution; tx=er.TX;
            t=find(string({tx.ID})==string(request.TransmitterID));
            assert(isscalar(t),id,'Missing original transmitter RF execution.');
            rf=tx(t).Replay.TXSignalDependency;
            localReceipt(rf,er,"sixgr.rf.executed_tx_signal_dependency/v1",id);
            assert(rf.ZeroPreserving&&rf.ZeroInputHistoryAtOrigin&& ...
                ~rf.AdditiveTXOutput&&rf.HistoryOriginSample<=history(r,1),id, ...
                'Additive TX output or unknown retained signal memory cannot be attributed to this component.');
            validateattributes(rf.MemorySamples,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
            validateattributes(rf.DelaySamples,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
            output=[max(channelInput(1),history(r,1)) min(channelInput(2),history(r,2))];
            input=[max(output(1)-rf.DelaySamples-rf.MemorySamples,rf.HistoryOriginSample) ...
                max(output(2)-rf.DelaySamples,rf.HistoryOriginSample)];
            if input(2)<=input(1), continue; end % Actual known-zero startup, not padded reference samples.
            localCoverage(history,input,id); cones(end+1,:)=input; %#ok<AGROW>
            operators{end+1,1}=struct('FFTWindowIndex',f,'FFTInterval',piece, ...
                'ChannelInputInterval',channelInput,'TXRFOutputInterval',output, ...
                'ComponentInputInterval',input,'Channel',d,'TXRF',rf); %#ok<AGROW>
            inputHit=find(history(:,1)<input(2)&history(:,2)>input(1));
            for h=inputHit.'
                eh=trace{h}.Execution; consumed=eh.ExecutedContributors;
                c=find(string({consumed.TransmitterID})==string(request.TransmitterID));
                th=find(string({eh.TX.ID})==string(request.TransmitterID));
                assert(isscalar(c)&&isscalar(th)&&consumed(c).CommittedThroughSample>=history(h,2),id, ...
                    'Only closed original contributor populations may establish absence.');
                receipt=consumed(c).Receipt;
                assert(string(receipt.Schema)=="consumed_waveform_components/v1"&& ...
                    isfield(receipt,'NonzeroIntervalSchema')&& ...
                    string(receipt.NonzeroIntervalSchema)=="exact_absolute_component_nonzero_runs/v1"&& ...
                    receipt.CompleteContributorList&& ...
                    receipt.StartSample==history(h,1)&&receipt.EndSampleExclusive==history(h,2)&& ...
                    receipt.SampleRateHz==request.SampleRateHz&& ...
                    string(receipt.CompositeInputSHA256)== ...
                        string(eh.TX(th).Replay.TXSignalDependency.OriginalInputChunkSHA256)&& ...
                    string(eh.TX(th).Replay.TXSignalDependency.RFInputWaveformSHA256)== ...
                        string(eh.TX(th).Replay.RFInputWaveformSHA256),id, ...
                    'The original consumed population must match the actual RF input, not queued intent.');
                local=[max(input(1),history(h,1)) min(input(2),history(h,2))];
                contributors{end+1,1}=struct('DependencyInterval',local, ...
                    'ExecutionInterval',history(h,:),'Receipt',receipt); %#ok<AGROW>
                for component=reshape(receipt.Components,1,[])
                    runs=localIntervals(component.NonzeroIntervals,id);
                    assert(component.StartSample>=history(h,1)&&component.EndSampleExclusive<=history(h,2)&& ...
                        all(runs(:,1)>=component.StartSample)&&all(runs(:,2)<=component.EndSampleExclusive)&& ...
                        component.NonzeroTimeSampleCount==sum(runs(:,2)-runs(:,1))&& ...
                        ((component.NonzeroSampleCount==0)==isempty(runs)),id, ...
                        'Exact original nonzero-run coverage is required; a whole prepared extent is insufficient.');
                    overlap=runs(runs(:,1)<local(2)&runs(:,2)>local(1),:);
                    if isempty(overlap), continue; end
                    overlap(:,1)=max(overlap(:,1),local(1)); overlap(:,2)=min(overlap(:,2),local(2));
                    if string(component.ComponentID)==string(request.ComponentID)
                        assert(string(component.OriginalSampleSHA256)==string(request.ComponentSHA256),id, ...
                            'The actual nonzero target contribution must be the original frozen component waveform.');
                        targetWindows(f)=true;
                    else
                        contamination(end+1)=struct('ComponentID',string(component.ComponentID), ...
                            'Intervals',overlap); %#ok<AGROW>
                    end
                end
            end
        end
    end
end
status="isolated_original_component_on_actual_FFT_support";
available=isempty(contamination)&&all(targetWindows);
if ~isempty(contamination), status="unavailable_non_target_component_in_finite_dependency";
elseif ~all(targetWindows), status="unavailable_no_target_signal_dependency";
end
proof=struct('ContractVersion',"sixgr.truth.EmittedComponentIsolation/v1", ...
    'Available',available,'Status',status,'Request',request, ...
    'ComponentDependencyIntervals',cones,'TargetDependencyPerFFTWindow',targetWindows, ...
    'OperatorReceipts',{operators},'ConsumedContributorReceipts',{contributors}, ...
    'Contamination',contamination,'Source',"original_successful_execution_finite_signal_dependency", ...
    'AdditionalRFExecutions',0,'AdditionalChannelExecutions',0, ...
    'PracticalReceiverInput',false,'AllHistoryComponentOnlyRequired',false);
end

function localReceipt(d,e,version,id)
assert(isstruct(d)&&isscalar(d)&&string(d.ContractVersion)==version&&d.Available&& ...
    d.StartSample==e.StartSample&&d.EndSampleExclusive==e.EndSampleExclusive&& ...
    d.SampleRateHz==e.SampleRateHz&&d.ConfigurationEpoch==e.ConfigurationEpoch,id, ...
    'Require an available original executed operator contract for this exact physical interval.');
end

function intervals=localIntervals(intervals,id)
assert(isnumeric(intervals)&&isreal(intervals)&&ismatrix(intervals),id,'Intervals must be numeric pairs.');
if isempty(intervals), intervals=zeros(0,2); return; end
if isvector(intervals)&&numel(intervals)==2, intervals=reshape(intervals,1,2); end
assert(size(intervals,2)==2&&all(isfinite(intervals),'all')&& ...
    all(intervals>=0,'all')&&all(intervals==fix(intervals),'all')&& ...
    all(intervals(:,2)>intervals(:,1))&&all(intervals(2:end,1)>=intervals(1:end-1,2)),id, ...
    'Use ordered nonoverlapping original half-open sample intervals.');
intervals=double(intervals);
end

function localCoverage(history,interval,id)
hit=history(:,1)<interval(2)&history(:,2)>interval(1);
assert(any(hit)&&history(find(hit,1),1)<=interval(1)&& ...
    history(find(hit,1,'last'),2)>=interval(2),id, ...
    'Retain all successful original execution covering the finite dependency cone.');
end
