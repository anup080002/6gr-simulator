function [reception,fields]=bindSharedCSIRSMeasurementPlane(reception,item,replay,owner)
% Bind unchanged practical CSI power to original executed element columns.
% No reference samples enter estimation, no numeric value is rescaled, and
% the original generic demodulation receipt remains immutable. This proves
% internal element identity only, never a connector or hardware reference.
fields=struct('PhysicalMeasurementReferencePlane',"unavailable_measurement_plane", ...
    'PhysicalMeasurementPlaneBindingAvailable',false, ...
    'PhysicalMeasurementPlaneBindingStatus',"unavailable_original_element_binding", ...
    'PhysicalMeasurementPlaneBindingJSON',"",'PhysicalMeasurementPlaneBindingSHA256',"", ...
    'PhysicalMeasurementStandardizedReferencePointQualified',false, ...
    'PhysicalMeasurementHardwareQualified',false);
if nargin==0, reception=struct(); return; end
id='sixgr:truth:CSIPhysicalPlaneBinding';
assert(nargin==4&&isa(owner,'sixgr.truth.CoupledWaveformStream')&& ...
    isstruct(item)&&isscalar(item)&&string(item.Kind)=="CSIRS"&& ...
    isscalar(string(item.ID))&&strlength(string(item.ID))>0,id, ...
    'Require the original shared CSI completion and physical owner.');
p=item.Context.Prepared;
assert(string(p.ExecutionStage)=="csirs_waveform_prepared_not_received"&& ...
    owner.Events.NextSampleIndex>=p.ReceiveEndSampleExclusive,id, ...
    'The original receive window must have completed.');
assert(reception.PhysicalMeasurementDemodulationReceiptAvailable,id, ...
    'Retain original practical measurement identity before binding its plane.');
token=string(reception.PhysicalMeasurementDemodulationReceiptJSON);
assert(isscalar(token)&&strlength(token)>0&& ...
    string(reception.PhysicalMeasurementDemodulationReceiptSHA256)== ...
    string(sixgr.util.sha256Hex(char(token))),id,'Original demodulation receipt changed.');
r=jsondecode(token);
assert(any(string(r.ContractVersion)==["sixgr.csirs.physical_demodulation/v1","sixgr.csirs.physical_demodulation/v2"])&& ...
    string(r.Source)=="original_CSI_RS_physical_measurement_demodulation"&& ...
    string(r.InputPlane)=="supplied_pre_composite_receiver_front_end_capture"&& ...
    ~r.AbsoluteObservationIdentityBound&&~r.ReceiveBranchLayoutQualified&& ...
    ~r.IndependentPowerReferenceAvailable&&~r.RSRPAccuracyQualified,id, ...
    'Preserve the generic receiver receipt without retrospectively upgrading it.');
rxID=string(replay.ReceiverID);
hit=find(string({item.Planes.ReceiverID})==rxID+":pre_rf");
assert(isscalar(hit),id,'One original pre-RF plane must belong to the executed receiver.');
pre=item.Planes(hit).Observation;
assert(isa(pre,'sixgr.phy.waveform.WaveformObservationBuffer')&&isscalar(pre)&& ...
    pre.isComplete()&&pre.StartSample==p.ReceiveStartSample&& ...
    pre.EndSampleExclusive==p.ReceiveEndSampleExclusive&&pre.SampleRateHz==p.SampleRateHz&& ...
    string(r.InputHashSerialization)=="WaveformHash.runtimeArray_class_dimensions_real_imag_double"&& ...
    pre.sampleHash()==string(r.InputSHA256)&& ...
    isequal(double(r.InputSize(:).'),[pre.EndSampleExclusive-pre.StartSample pre.NumReceiveAntennas])&& ...
    r.NumReceiveChannels==pre.NumReceiveAntennas&& ...
    isequal(double(r.ReceiveChannelIndices0(:).'),0:pre.NumReceiveAntennas-1)&& ...
    r.FFTSupport.SampleRateHz==pre.SampleRateHz&& ...
    string(r.WaveformAmplitudeUnit)==string(replay.WaveformAmplitudeUnit),id, ...
    'Measurement samples, ordering, units and clock must match the original capture.');
element=sixgr.rf.validateReceiveElementObservation(pre,replay, ...
    owner.Physical.receiveElementLayout(rxID));
obs=reception.CSIRSObservation;
fields.PhysicalMeasurementReferencePlane=string(obs.PhysicalMeasurementReferencePlane);
fields.PhysicalMeasurementPlaneBindingAvailable=element.Available;
fields.PhysicalMeasurementPlaneBindingStatus=string(element.Status);
evidence=struct('ContractVersion',"sixgr.csirs.original_measurement_plane/v1", ...
    'ReceiverWindowID',string(item.ID),'ReceiverID',rxID, ...
    'ObservationStartSample',pre.StartSample,'ObservationEndSampleExclusive',pre.EndSampleExclusive, ...
    'SampleRateHz',pre.SampleRateHz,'OriginalInputSHA256',string(r.InputSHA256), ...
    'OriginalDemodulationReceiptSHA256',string(reception.PhysicalMeasurementDemodulationReceiptSHA256), ...
    'ReceiveElementBinding',element,'ReceiverMeasurementValuesChanged',false, ...
    'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0, ...
    'StandardizedReferencePointQualified',false,'HardwareQualified',false);
if element.Available
    fields.PhysicalMeasurementReferencePlane=string(element.ReferencePlane);
    obs.PhysicalMeasurementReferencePlane=fields.PhysicalMeasurementReferencePlane;
    % Normalized units remain explicit even when spatial ordering is known.
    if ~obs.MeasurementPowerReferenceNormalized
        obs.PowerReferencePlane=fields.PhysicalMeasurementReferencePlane;
    end
end
fields.PhysicalMeasurementPlaneBindingJSON=string(jsonencode(evidence));
fields.PhysicalMeasurementPlaneBindingSHA256=string(sixgr.util.sha256Hex( ...
    char(fields.PhysicalMeasurementPlaneBindingJSON)));
reception.CSIRSObservation=obs;
end
