function T=exportSharedPDSCHCSIRSComparison(root,T,snapshot,prepared,source,captures,owner,item,varargin)
% Private post-reception engineering comparison; immutable exact operands.
assert(istable(T) && height(T)==1 && isfolder(root), ...
    'sixgr:truth:PairedChannelPublication','One actual completed source row and existing output root required.');
T.DMRSCSIRSComparisonAvailable=false;
T.DMRSCSIRSComparisonStatus="unavailable_no_common_received_estimates";
T.DMRSCSIRSComparisonObservationID=""; T.DMRSCSIRSComparisonMATFile="";
T.DMRSCSIRSComparisonMATFileSHA256=""; T.DMRSCSIRSComparisonCSV=""; T.DMRSCSIRSComparisonCSVSHA256="";
comparisons=sixgr.truth.scoreSharedPDSCHCSIRSComparison(snapshot,prepared,source,captures,owner,item,varargin{:});
if isempty(comparisons), return; end
rows=table();
for k=1:numel(comparisons)
    part=comparisons(k).Rows;
    if isempty(part), continue; end
    part.ResourceID=repmat(comparisons(k).ResourceID,height(part),1);
    part.ResourceOrdinal0=repmat(comparisons(k).ResourceOrdinal0,height(part),1);
    rows=[rows;part]; %#ok<AGROW>
end
T.DMRSCSIRSComparisonStatus=strjoin(unique(string({comparisons.Status}),'stable'),"|");
if isempty(rows), return; end
T.DMRSCSIRSComparisonAvailable=any(arrayfun(@(c)isfield(c.Score,'Available') && c.Score.Available,comparisons));
assert(all(ismember({'ChannelObservationID','ReceiverObservationSHA256'},T.Properties.VariableNames)), ...
    'sixgr:truth:PairedChannelPublicationIdentity','Original channel and received-sample identities must survive.');
identity=struct('ChannelObservationID',string(T.ChannelObservationID), ...
    'ReceiverObservationSHA256',string(T.ReceiverObservationSHA256), ...
    'ReceiverWindowID',string(item.ID),'TransmissionID',string(item.Context.TransmissionIdentity.TransmissionID));
bound=comparisons(find(arrayfun(@(c)~isempty(fieldnames(c.Evidence)),comparisons),1)).Evidence;
for k=1:numel(comparisons)
    if isempty(fieldnames(comparisons(k).Evidence)), continue; end
    assert(isequaln(comparisons(k).Evidence.ReceiverPlaneBinding,bound.ReceiverPlaneBinding), ...
        'sixgr:truth:PairedChannelPublicationIdentity','All resource estimates must use the same original receiver input.');
end
for name=string(fieldnames(bound.ReceiverPlaneBinding.ReceiverInput)).'
    assert(ismember(name,T.Properties.VariableNames) && ...
        isequaln(T.(name),bound.ReceiverPlaneBinding.ReceiverInput.(name)), ...
        'sixgr:truth:PairedChannelPublicationIdentity','The source row must retain the original decoder-input %s.',name);
end
identity.PostRFSampleSHA256=bound.PostRFSampleSHA256;
identity.ReceiverPlaneBindingSHA256=bound.ReceiverPlaneBindingSHA256;
identity.Population=localPopulation(prepared,T,owner,item);
sourceRow=T;
values=table2array(rows);
token=sixgr.phy.waveform.WaveformHash.bytes(string(jsonencode(identity))+"|"+ ...
    sixgr.phy.waveform.WaveformHash.runtimeArray(values));
observationID="paired_dmrs_csirs_"+string(token);
relative="channel_estimation/csv/"+observationID+".csv";
matRelative="channel_estimation/mat/"+observationID+".mat";
csvPath=fullfile(root,relative); matPath=fullfile(root,matRelative);
assert(~isfile(csvPath) && ~isfile(matPath),'sixgr:truth:DuplicatePairedChannelPublication', ...
    'Never overwrite an earlier immutable comparison.');
rows.DMRSCSIRSComparisonObservationID=repmat(observationID,height(rows),1);
sixgr.util.csvWriteTable(csvPath,rows,'PreserveSchema',true,'RoundTripNumericText',true);
csvHash=string(sixgr.phy.waveform.WaveformHash.file(csvPath));
payload=struct('Contract',"same_execution_paired_DMRS_CSI_RS_archive/v2", ...
    'ObservationID',observationID,'Identity',identity,'SourceRow',sourceRow, ...
    'Comparisons',comparisons,'Resources',rows,'ResourcesCSVSHA256',csvHash, ...
    'ReferenceUsedByReceiver',false,'StatisticallyQualified',false);
sixgr.util.matSave(matPath,payload,'UseArtifactStore',false);
saved=sixgr.util.csvReadTable(csvPath,'TextType','string');
assert(isequaln(saved,rows),'sixgr:truth:PairedChannelCSVClosure', ...
    'Every original compared value, resource coordinate and energy must roundtrip exactly.');
readback=load(matPath);
assert(isequaln(readback.Comparisons,comparisons) && isequaln(readback.SourceRow,sourceRow), ...
    'sixgr:truth:PairedChannelMATClosure','Retain complex operands/maps and exact source-row metadata.');
T.DMRSCSIRSComparisonObservationID=observationID;
T.DMRSCSIRSComparisonMATFile=matRelative;
T.DMRSCSIRSComparisonMATFileSHA256=string(sixgr.phy.waveform.WaveformHash.file(matPath));
T.DMRSCSIRSComparisonCSV=relative; T.DMRSCSIRSComparisonCSVSHA256=csvHash;
end

function population=localPopulation(prepared,row,owner,item)
% The original preparation token is a separate namespace from supplied row
% labels and from CSI's own TX population. Never fill one from another.
population=struct('PreparedDataPopulation',struct(),'PreparedDataPopulationJSON',"", ...
    'PreparedDataPopulationSHA256',"",'OriginalSourceRowPopulation',struct());
names=["RunID","SourceRunID","RunFolder","RunTag","ExecutionID","ConfigHash","ScenarioID", ...
    "Seed","RandomSeed","ChannelSeed","SourceRandomSeed","SourceChannelSeed", ...
    "PreparedRandomSeed","PreparedChannelSeed","SweepPointIndex","ConfiguredSNR_dB"];
for key=names
    if ismember(key,row.Properties.VariableNames), population.OriginalSourceRowPopulation.(key)=row.(key); end
end
cfg=prepared.InputConfig; runtime=sixgr.util.structGet(cfg,'lls6g.runtime',struct());
has=isfield(runtime,'PreparedDataPopulation');
assert(has==isfield(runtime,'PreparedDataPopulationSHA256'), ...
    'sixgr:truth:PairedPreparedPopulation','The original token and hash must survive together.');
if ~has, return; end % Historical absence does not authorize reconstruction.
p=runtime.PreparedDataPopulation;
required={'Version','Source','RunID','ExecutionID','ConfigHash','ScenarioID', ...
    'PreparedRandomSeed','PreparedChannelSeed','SourceRandomSeed','SourceChannelSeed', ...
    'SweepPointIndex','ConfiguredSNR_dB','UEIndex','Direction','GrantContextID', ...
    'CapturedAtSample','ReceiverClockDomain','ReceiverClockEpoch'};
assert(isstruct(p) && isscalar(p) && all(isfield(p,required)) && ...
    string(p.Version)=="prepared_data_population/v1" && ...
    string(p.Source)=="shared_coordinator_before_data_preparation", ...
    'sixgr:truth:PairedPreparedPopulation','Retain the original preparation population contract.');
token=string(jsonencode(sixgr.util.jsonSafeValue(p)));
sha=string(sixgr.util.sha256Hex(uint8(unicode2native(char(token),'UTF-8'))));
emitted=owner.DataTransmissions;
emitted=emitted(arrayfun(@(r)r.Identity.TransmissionID==item.Context.TransmissionIdentity.TransmissionID,emitted));
assert(isscalar(emitted),'sixgr:truth:PairedPreparedPopulation','Retain the unique actual first-active data receipt.');
assert(sha==string(runtime.PreparedDataPopulationSHA256) && ...
    string(p.RunID)==string(sixgr.util.structGet(cfg,'run.runTag',"")) && ...
    string(p.ExecutionID)==string(sixgr.util.structGet(cfg,'run.executionID',"")) && ...
    string(p.ConfigHash)==string(sixgr.util.structGet(cfg,'meta.configHash',"")) && ...
    string(p.ScenarioID)==string(sixgr.util.structGet(cfg,'run.scenarioID',"")) && ...
    isequaln(double(p.PreparedRandomSeed),double(sixgr.util.structGet(cfg,'run.seed',NaN))) && ...
    isequaln(double(p.PreparedChannelSeed),double(sixgr.util.structGet(cfg,'channel.seed',NaN))) && ...
    isequaln(double(p.ConfiguredSNR_dB),double(sixgr.util.structGet(prepared.RequestBinding,'SNR_dB',NaN))) && ...
    p.UEIndex==item.UE && string(p.Direction)==prepared.Direction && ...
    string(p.GrantContextID)==string(prepared.RequestBinding.PHYGrant.GrantContextId) && ...
    string(p.ReceiverClockDomain)=="shared_receiver_sample_clock/v1" && ...
    p.ReceiverClockEpoch==owner.Physical.ConfigurationEpoch && ...
    isfinite(p.CapturedAtSample) && p.CapturedAtSample>=0 && p.CapturedAtSample==fix(p.CapturedAtSample) && ...
    p.CapturedAtSample<=emitted.FirstActiveSample, ...
    'sixgr:truth:PairedPreparedPopulation','Never relabel source seeds/point or substitute current callback context.');
if isfield(p,'LogicalGrantContextID') && strlength(string(p.LogicalGrantContextID))>0
    assert(string(p.LogicalGrantContextID)==string(prepared.RequestBinding.Grant.GrantContextId), ...
        'sixgr:truth:PairedPreparedPopulation','Logical and frozen PHY grant identities remain distinct.');
end
population.PreparedDataPopulation=p; population.PreparedDataPopulationJSON=token;
population.PreparedDataPopulationSHA256=sha;
end
