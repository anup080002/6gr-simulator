function [metrics,pairs]=pairCSIRSReceivedAggregate(measured,reference,support,context,trace,request)
% Original pre-RX aggregate CSI component; never logical-port attribution.
metrics=struct('Available',false,'Status',"unavailable_original_component_isolation", ...
    'EVM_rms',NaN,'ErrorEnergy',NaN,'ReferenceEnergy',NaN,'SampleCount',0, ...
    'ReferencePlane',"internal_physical_receive_element_before_RX_front_end", ...
    'Definition',"sqrt_sum_received_minus_original_emitted_desired_grid_error_over_reference_energy", ...
    'IncludesOriginalTXDistortion',true,'IncludesReceiverRF',false, ...
    'GainOrPhaseFitted',false,'ReferenceUsedByReceiver',false, ...
    'StandardizedAccuracyQualified',false,'RFConformanceQualified',false, ...
    'PowerUnitQualified',false,'StandardizedReferencePointQualified',false,'HardwareQualified',false);
pairs=struct([]);
proof=sixgr.truth.proveEmittedComponentIsolation(trace,request);
metrics.IsolationEvidenceJSON=string(jsonencode(proof));
metrics.IsolationEvidenceSHA256=sixgr.util.sha256Hex(char(metrics.IsolationEvidenceJSON));
if ~(islogical(proof.Available)&&isscalar(proof.Available)&&proof.Available)
    metrics.Status=string(proof.Status); return;
end
id='sixgr:truth:CSIRSReceivedEVMIdentity';
assert(isequal(size(measured),size(reference))&&isnumeric(measured)&&isnumeric(reference)&& ...
    all(isfinite(measured),'all')&&all(isfinite(reference),'all'),id,'Original grids must be complete and identical in shape.');
assert(size(support,2)==2&&~isempty(support)&&all(isfinite(support),'all')&& ...
    all(support==fix(support),'all')&&all(support>=0,'all')&& ...
    isequal(support,unique(support,'rows','sorted'))&& ...
    all(support(:,1)<size(measured,1))&&all(support(:,2)<size(measured,2)),id, ...
    'Use the unique union of original physical CSI REs, never count logical ports twice.');
assert(string(context.OriginalNoisyGridSHA256)==sixgr.phy.waveform.WaveformHash.numeric(measured)&& ...
    string(context.DesiredGridSHA256)==sixgr.phy.waveform.WaveformHash.numeric(reference)&& ...
    string(context.ParentComponentID)==string(request.ComponentID)&& ...
    context.SampleRateHz==request.SampleRateHz&&context.ConfigurationEpoch==request.ConfigurationEpoch, ...
    id,'Original grids, parent and execution identity must match the completed owner.');
idx=sub2ind([size(measured,1),size(measured,2)],support(:,1)+1,support(:,2)+1);
errorEnergy=0; referenceEnergy=0;
for branch=1:size(measured,3)
    y=measured(:,:,branch); d=reference(:,:,branch); y=y(idx); d=d(idx);
    errorEnergy=errorEnergy+sum(abs(y-d).^2); referenceEnergy=referenceEnergy+sum(abs(d).^2);
    q=struct('SignalName',"CSI-RS",'PortIndex',branch-1, ...
        'PortRole',"physical_RX_element_aggregate_CSI_not_logical_port", ...
        'ObservationID',string(context.ObservationID), ...
        'ObservationStartSample',context.StartSample,'ObservationEndSampleExclusive',context.EndSampleExclusive, ...
        'ObservationSampleRateHz',context.SampleRateHz, ...
        'SampleIndex',double(idx-1),'ReferenceReal',real(d),'ReferenceImag',imag(d), ...
        'MeasuredReal',real(y),'MeasuredImag',imag(y), ...
        'ReferenceSource',"same_execution_isolated_emitted_aggregate_CSI_pre_RX_grid", ...
        'ReferencePlane',metrics.ReferencePlane,'EVMDefinition',metrics.Definition, ...
        'MeasurementDomain',"pre_RX_front_end_received_physical_CSI_RE_union", ...
        'AlignmentSource',"original_practical_pre_RX_timing_CFO_FFT_operator_no_fit", ...
        'GainOrPhaseFitted',false,'ReceiverUsesScoringReference',false, ...
        'IsolatedComponentProved',true,'IsolationEvidenceSHA256',metrics.IsolationEvidenceSHA256, ...
        'OriginalDemodulationReceiptSHA256',string(context.OriginalDemodulationReceiptSHA256), ...
        'OriginalNoisyGridSHA256',string(context.OriginalNoisyGridSHA256), ...
        'OriginalDesiredGridSHA256',string(context.DesiredGridSHA256), ...
        'WaveformAmplitudeUnit',string(context.WaveformAmplitudeUnit), ...
        'RFConformanceQualified',false,'StandardizedAccuracyQualified',false, ...
        'PowerUnitQualified',false,'StandardizedReferencePointQualified',false,'HardwareQualified',false);
    if isempty(pairs), pairs=q; else, pairs(end+1)=q; end %#ok<AGROW>
end
assert(isfinite(referenceEnergy)&&referenceEnergy>0,id,'Original received reference energy must be positive.');
metrics.Available=true; metrics.Status="measured_original_isolated_aggregate_received_CSI_pre_RX_not_conformance";
metrics.ErrorEnergy=errorEnergy; metrics.ReferenceEnergy=referenceEnergy;
metrics.EVM_rms=sqrt(errorEnergy/referenceEnergy); metrics.SampleCount=numel(idx)*size(measured,3);
metrics.SupportSHA256=sixgr.phy.waveform.WaveformHash.runtimeArray(support);
end
