function state=retainReceivedPUCCHTimingReference(state,ue,cfg,assignment,context,observation,rx)
% Retain successful independent DM-RS acquisition, not a decoded UCI value
% or a prepared-transmitter timing origin. Format 0 cannot refresh itself.
assert(isa(assignment,'sixgr.phy.pucch.PUCCHReceptionAssignment') && isscalar(assignment) && ...
    isa(context,'sixgr.phy.pucch.UCIReportContext') && isscalar(context), ...
    'sixgr:truth:PUCCHTimingReceiverIdentity','Use the independently installed gNB receive hypothesis.');
if assignment.Format==0, return; end
assert(isstruct(rx) && isscalar(rx) && ...
    rx.AssignmentDigest==assignment.Digest && rx.ReportContextDigest==context.Digest && ...
    assignment.ReportContextDigest==context.Digest && rx.IndependentReceiverAssignment && ...
    ~rx.PreparedTransmitterConsumed && ~rx.InjectedNoiseVarianceConsumed && ...
    ~rx.InjectedInterferenceCovarianceConsumed && ~rx.OraclePayloadBitsUsed, ...
    'sixgr:truth:PUCCHTimingReceiverIdentity','Do not retain transmitter-derived or mismatched receiver timing.');
for field=["ReceiverUsable","DTX","CRCPassed","ChannelEstimateApplicable","ResourceExtractionAvailable"]
    value=sixgr.util.structGet(rx,field,[]);
    assert((islogical(value)||isnumeric(value)) && isscalar(value) && ...
        isreal(value) && isfinite(value) && any(value==[0 1]), ...
        'sixgr:truth:InvalidPUCCHTimingEvidence','Receiver field %s must be an explicit boolean.',field);
end
if ~rx.ReceiverUsable || rx.DTX || ~rx.CRCPassed, return; end
assert(rx.ChannelEstimateApplicable && rx.ResourceExtractionAvailable && ...
    rx.ReceiverObservationStartSample==observation.StartSample && ...
    rx.ReceiverObservationEndSampleExclusive==observation.EndSampleExclusive && ...
    rx.ReceiverObservationSampleRateHz==observation.SampleRateHz, ...
    'sixgr:truth:InvalidPUCCHTimingEvidence','Bind received DM-RS timing to its actual completed sample buffer.');
reference=sixgr.phy.sync.ReceivedULTimingReference(assignment,observation,rx.ReceiveTiming,cfg);
state=sixgr.truth.storeReceivedULTimingReference(state,ue,reference);
end
