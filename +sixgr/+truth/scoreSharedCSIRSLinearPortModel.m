function e=energyClosure(terms,total,support,nfft,unit)
K=size(total,1); nrx=size(total,3); idx=sub2ind([K size(total,2)],support(:,1)+1,support(:,2)+1);
scale=1; if unit=="sqrt_mW", scale=double(nfft)*sqrt(1000); end
values=cell(1,4); powers=zeros(4,nrx); cross=zeros(6,nrx); pairs=zeros(6,2); combined=[];
for k=1:4
    flat=reshape(double(terms{k}),[],nrx); values{k}=flat(idx,:)/scale;
    powers(k,:)=mean(abs(values{k}).^2,1);
    if k==1, combined=values{k}; else, combined=combined+values{k}; end
end
n=0;
for i=1:3
    for j=i+1:4
        n=n+1; pairs(n,:)=[i j]; cross(n,:)=2*real(mean(conj(values{i}).*values{j},1));
    end
end
flat=reshape(double(total),[],nrx); observed=flat(idx,:)/scale;
closeSamples(observed,combined,'Target/other/residual/external complex samples must close.');
actual=mean(abs(observed).^2,1); sumPower=sum(powers,1)+sum(cross,1);
bound=256*max(1,size(observed,1))*eps(max(realmin('double'),max([abs(actual(:));abs(powers(:));abs(cross(:))])));
assert(all(abs(actual-sumPower)<=bound),'sixgr:truth:CSIRSLinearModelClosure', ...
    'Signed cross terms must close the original composite power within accumulation roundoff.');
e=struct('TermOrder',["target","other_linear_including_common_DC","nonlinear_DAC_model_residual","external_and_noise"], ...
    'SupportSHA256',hash(support),'RECount',size(support,1),'RawGridAmplitudeDivisor',scale, ...
    'PowerPerTermPerReceiveColumn',powers,'CrossPairIndices1',pairs, ...
    'SignedCrossPowerPerReceiveColumn',cross,'OriginalCompositePowerPerReceiveColumn',actual, ...
    'PowerClosureResidualPerReceiveColumn',actual-sumPower,'NumericalRoundoffBound',bound, ...
    'PowerAdditivityAssumed',false,'PhysicalAccuracyThresholdApplied',false);
end
function closeSamples(a,b,message)
assert(isequal(size(a),size(b))&&all(isfinite(a),'all')&&all(isfinite(b),'all'), ...
    'sixgr:truth:CSIRSLinearModelClosure','Finite equal-shaped original model operands are required.');
scale=max(realmin('double'),max([abs(double(a(:)));abs(double(b(:)))]));
bound=256*max(1,ceil(log2(max(2,numel(a)))))*eps(scale);
assert(max(abs(double(a(:))-double(b(:))))<=bound,'sixgr:truth:CSIRSLinearModelClosure','%s',message);
end
