function result=scoreSharedCSIRSLinearPortModel(item,reception,desired,source,replay,owner)
% Optional POST-receiver comparison with the ORIGINAL fixed-linear model.
% A target is a homogeneous, widely-linear port-3000 model contribution.
% Aggregate includes common IQ DC exactly once and all original TX signals.
% Residual includes nonlinear PA, DAC and model/roundoff differences. None
% is a unique physical attribution of nonlinear output to logical ports.
% No reference enters acquisition, Hest, CSI feedback or scheduler state.
% Supported producer domain is CPU double. Captures must contain complete
% original processor intervals; a clipped interval cannot be authenticated
% from its full-chunk digest and is rejected, never implicitly equated.
[result,e]=emptyResult();
if nargin==0, return; end
assert(nargin==6,'sixgr:truth:CSIRSLinearModelArguments', ...
    'Supply the original completed item, reception, desired plane, source, replay and owner.');
try
    if ~isfield(item.Context,'CSIRSPortReferencePlanes') || isempty(item.Context.CSIRSPortReferencePlanes)
        return; % Optional producer was not installed; do not invent evidence.
    end
    id='sixgr:truth:CSIRSLinearModelIdentity';
    e.Stage="original_owner_and_measurement_binding";
    assert(isa(owner,'sixgr.truth.CoupledWaveformStream')&&string(item.Kind)=="CSIRS",id, ...
        'Require the original shared CSI completion.');
    p=item.Context.Prepared; c=p.Carrier; obs=reception.CSIRSObservation;
    assert(string(p.ExecutionStage)=="csirs_waveform_prepared_not_received"&& ...
        owner.Events.NextSampleIndex>=p.ReceiveEndSampleExclusive&& ...
        isequal(reception.PhysicalMeasurementDemodulationReceiptAvailable,true),id, ...
        'The practical receiver and original observation must have completed first.');
    token=string(reception.PhysicalMeasurementDemodulationReceiptJSON);
    assert(isscalar(token)&&strlength(token)>0&& ...
        sha(token)==string(reception.PhysicalMeasurementDemodulationReceiptSHA256),id, ...
        'Original practical operator token and hash differ.');
    r=jsondecode(token);
    assert(string(r.ContractVersion)=="sixgr.csirs.physical_demodulation/v1"&& ...
        string(r.Source)=="original_CSI_RS_physical_measurement_demodulation"&& ...
        string(r.InputPlane)=="supplied_pre_composite_receiver_front_end_capture"&& ...
        string(r.InputHashSerialization)=="WaveformHash.runtimeArray_class_dimensions_real_imag_double"&& ...
        isequal(r.IndependentPowerReferenceAvailable,false)&&isequal(r.RSRPAccuracyQualified,false)&& ...
        isequal(r.AbsoluteObservationIdentityBound,false)&&isequal(r.ReceiveBranchLayoutQualified,false)&& ...
        r.AdditionalTimingAcquisitions==0&&r.AdditionalOFDMDemodulations==0,id, ...
        'Preserve the original practical operator without promoting its authority.');
    pre=plane(item,string(source.ReceiverID)+":pre_rf",p);
    tx=plane(item,string(item.Context.TransmitterPlane),p,false);
    originalDesired=plane(item,string(item.Context.DesiredReferencePlane),p);
    assert(originalDesired.Observation==desired&& ...
        string(source.Source)=="actual_executed_link_contribution"&& ...
        string(source.ReceiverID)==string(replay.ReceiverID)&& ...
        string(source.TransmitterID)+":tx"==string(item.Context.TransmitterPlane)&& ...
        source.StartSample==pre.Observation.StartSample&& ...
        source.EndSampleExclusive==pre.Observation.EndSampleExclusive&& ...
        isequal(source.ReceiverEstimatorInput,false)&& ...
        source.AdditionalRFExecutions==0&&source.AdditionalChannelExecutions==0,id, ...
        'Retain the original desired-link instance, endpoint and sample window.');
    nrx=pre.Observation.NumReceiveAntennas;
    assert(pre.Observation.sampleHash()==string(r.InputSHA256)&& ...
        numericVectorEqual(r.InputSize,[pre.Observation.EndSampleExclusive-pre.Observation.StartSample nrx])&& ...
        numericScalarEqual(r.NumReceiveChannels,nrx)&&numericVectorEqual(r.ReceiveChannelIndices0,0:nrx-1)&& ...
        string(r.InputClass)=="double"&&isa(p.TransmitSamples,'double')&& ...
        desired.NumReceiveAntennas==nrx&&isequal(r.WaveformAmplitudeUnitRecognized,true)&& ...
        string(r.WaveformAmplitudeUnit)==string(replay.WaveformAmplitudeUnit)&& ...
        string(r.WaveformAmplitudeUnit)==string(p.PowerContext.WaveformAmplitudeUnit),id, ...
        'Original samples, receive-column order and units must agree.');
    element=sixgr.rf.validateReceiveElementObservation(pre.Observation,replay, ...
        owner.Physical.receiveElementLayout(string(source.ReceiverID)));
    assert(isequal(element.Available,true),id,'Original element execution binding is required.');
    refs=item.Context.CSIRSPortReferencePlanes;
    resources=p.Tx.CSIRSInfo.Resources;
    measured=obs.MeasurementPhysicalResources;
    recorded=r.Resources; if iscell(recorded), recorded=vertcat(recorded{:}); end
    assert(isstruct(resources)&&~isempty(resources)&&iscell(measured)&& ...
        numel(resources)==numel(measured)&&numel(refs)==numel(resources)&& ...
        numel(recorded)==numel(resources)&& ...
        string(obs.MeasurementPhysicalResourcesJSON)== ...
            string(jsonencode(sixgr.util.jsonSafeValue(measured))),id, ...
        'All original resources and measured values must be retained, in original order.');
    assert(all(arrayfun(@(v)numericScalarEqual(v.ResourceID,v.ResourceID),resources))&& ...
        all(arrayfun(@(v)numericScalarEqual(v.ResourceID,v.ResourceID)&& ...
        numericScalarEqual(v.ResourceOrdinal0,v.ResourceOrdinal0),recorded))&& ...
        all(arrayfun(@(v)numericScalarEqual(v.ResourceID,v.ResourceID)&& ...
        numericScalarEqual(v.ResourceSetID,r.ResourceSetID)&& ...
        numericScalarEqual(v.LogicalPortIndex0,0)&&numericScalarEqual(v.ReferencePortNumber,3000),refs)),id, ...
        'Resource identities must be original finite numeric scalars.');
    ids=double([resources.ResourceID]);
    assert(numel(unique(ids))==numel(ids)&&isequal(double([recorded.ResourceID]),ids)&& ...
        isequal(double([recorded.ResourceOrdinal0]),0:numel(ids)-1)&& ...
        isequal(double([refs.ResourceID]),ids)&&all([refs.LogicalPortIndex0]==0)&& ...
        all([refs.ReferencePortNumber]==3000),id, ...
        'Do not reorder, omit or replace an original resource/port population.');
    parent=bindParent(owner,item,p,source,tx,r,refs);
    supports=cell(numel(resources),1); allSupport=cell(numel(resources),1);
    K=12*double(c.NSizeGrid); L=double(c.SymbolsPerSlot);
    for k=1:numel(resources)
        a=resources(k); b=recorded(k); m=measured{k};
        assert(isnumeric(a.Indices)&&isreal(a.Indices)&&all(isfinite(a.Indices),'all'),id, ...
            'Original logical pilot indices must remain numeric.');
        index=double(a.Indices(:));
        assert(~isempty(index)&&all(index==fix(index))&&all(index>=1&index<=K*L*a.NumPorts)&& ...
            numericScalarEqual(b.NumPorts,a.NumPorts)&&numericScalarEqual(b.RowNumber,a.RowNumber)&& ...
            numericScalarEqual(b.NumRB,a.NumRB)&&numericScalarEqual(b.RBOffset,a.RBOffset)&& ...
            string(b.CDMType)==string(a.CDMType)&& ...
            string(b.LogicalPilotIndicesSHA256)==hash(a.Indices)&& ...
            string(b.LogicalPilotSymbolsSHA256)==hash(a.Symbols),id,'Original logical resource changed.');
        base=unique(index(index<=K*L)-1,'sorted');
        supports{k}=[mod(base,K) floor(base/K)];
        base=unique(mod(index-1,K*L),'sorted'); allSupport{k}=[mod(base,K) floor(base/K)];
        assert(~isempty(supports{k})&&hash(supports{k})==string(b.Port3000SupportSHA256)&& ...
            numericScalarEqual(b.Port3000RECount,size(supports{k},1))&& ...
            numericScalarEqual(b.LogicalPilotCount,numel(index))&& ...
            numericScalarEqual(b.PhysicalRECount,size(allSupport{k},1))&& ...
            hash(allSupport{k})==string(b.PhysicalSupportSHA256)&& ...
            isstruct(m)&&isscalar(m)&&numericScalarEqual(m.ResourceID,a.ResourceID)&& ...
            numericScalarEqual(m.RSRPReferencePort,3000)&&numericScalarEqual(m.NumReceiveAntennas,nrx)&& ...
            numericScalarEqual(m.NumRB,a.NumRB)&& ...
            numericScalarEqual(m.FirstPRB0Based,double(c.NStartGrid)+a.RBOffset)&& ...
            numericScalarEqual(m.SubcarrierSpacing_kHz,double(c.SubcarrierSpacing))&& ...
            numericVectorEqual(m.SymbolIndices0Based,unique(supports{k}(:,2))),id, ...
            'The measured resource and exact port-3000 support must match original operands.');
    end
    supportUnion=unique(vertcat(allSupport{:}),'rows','sorted');
    [f,frequency]=operator(r,reception,p,supportUnion);
    unit=string(r.WaveformAmplitudeUnit); normalized=unit=="normalized_complex_baseband";
    powerUnit="W_resource_grid"; suffix="_dBm"; scale=f.Nfft*sqrt(1000);
    if normalized, powerUnit="relative_to_unit_occupied_RE_Es"; suffix="_dB_re_UnitOccupiedRE_Es"; scale=NaN; end
    assert(isequal(obs.MeasurementPowerReferenceNormalized,normalized)&& ...
        numericScalarEqual(obs.MeasurementFFTSize,f.Nfft)&&isequaln(obs.MeasurementGridScaleToSqrtW,scale)&& ...
        numericScalarEqual(obs.MeasurementReceiverGainCorrection_dB,0)&& ...
        string(obs.MeasurementReceiverGainCorrectionSource)== ...
        "not_required_exact_pre_front_end_measurement_waveform",id,'Original measurement scaling changed.');
    e.ObservationID=string(item.ID); e.ParentComponentID=string(item.Context.ComponentID);
    e.LinkID=string(source.LinkID); e.TransmitterID=string(source.TransmitterID);
    e.ReceiverID=string(source.ReceiverID); e.ConfigurationEpoch=owner.Physical.ConfigurationEpoch;
    e.StartSample=pre.Observation.StartSample; e.EndSampleExclusive=pre.Observation.EndSampleExclusive;
    e.SampleRateHz=pre.Observation.SampleRateHz; e.ReceiveElementBinding=element;
    e.OriginalDemodulationReceiptSHA256=sha(token);
    e.OriginalMeasurementResourcesSHA256=sha(string(obs.MeasurementPhysicalResourcesJSON));
    e.OriginalParentRegistrationSHA256=parent.RegistrationSHA256;
    e.OriginalEnqueueReceiptSHA256=parent.Receipt.ReceiptSHA256;
    e.OriginalOperator=r; e.ReferencePlane=string(element.ReferencePlane);
    e.WaveformAmplitudeUnit=unit;
    e.Stage="committed_original_model_planes";
    aggregate=plane(item,string(item.Context.CSIModelAggregatePlane),p);
    residual=plane(item,string(item.Context.CSIModelResidualPlane),p);
    a=aggregate.Observation.readComplete(); d=desired.readComplete(); z=residual.Observation.readComplete();
    e.AggregateIntervals=bindAggregate(aggregate,residual,originalDesired,source,owner);
    closeSamples(d,a+z,'Original aggregate plus residual must close against the executed desired link.');
    e.Stage="recorded_original_native_operator";
    e.AdditionalOFDMDemodulationAttempts=e.AdditionalOFDMDemodulationAttempts+1;
    [Y,noisyAligned]=demod(pre.Observation.readComplete(),c,r,frequency);
    e.AdditionalOFDMDemodulations=e.AdditionalOFDMDemodulations+1;
    assert(noisyAligned==string(r.AlignedSHA256)&&numericHash(Y)==string(r.GridSHA256),id, ...
        'The recorded original operator must reproduce the ORIGINAL noisy aligned input and grid exactly.');
    e.AdditionalOFDMDemodulationAttempts=e.AdditionalOFDMDemodulationAttempts+3;
    [D,~]=demod(d,c,r,frequency); [A,~]=demod(a,c,r,frequency); [R,~]=demod(z,c,r,frequency);
    e.AdditionalOFDMDemodulations=e.AdditionalOFDMDemodulations+3;
    closeSamples(D,A+R,'Original model grids must close after the same linear receiver operator.');
    X=Y-D; % Other links and original receiver noise, not another noise draw.
    e.OriginalDesiredInputSHA256=desired.sampleHash();
    e.AggregateInputSHA256=aggregate.Observation.sampleHash();
    e.ResidualInputSHA256=residual.Observation.sampleHash();
    e.OriginalNoisyGridSHA256=numericHash(Y); e.DesiredGridSHA256=numericHash(D);
    e.AggregateGridSHA256=numericHash(A); e.ResidualGridSHA256=numericHash(R);
    e.ResourceComparisons=cell(numel(resources),1);
    for k=1:numel(resources)
        target=plane(item,string(refs(k).PlaneID),p);
        intervals=bindTarget(target,refs(k),parent,source,owner,unit);
        e.AdditionalOFDMDemodulationAttempts=e.AdditionalOFDMDemodulationAttempts+1;
        [T,~]=demod(target.Observation.readComplete(),c,r,frequency);
        e.AdditionalOFDMDemodulations=e.AdditionalOFDMDemodulations+1;
        m=measured{k};
        assert(string(m.PowerUnit)==powerUnit&&string(m.SINR.PowerUnit)==powerUnit,id,'Original power units differ.');
        power=sixgr.phy.refsig.compareCSIRSPowerReference(T,supports{k},f.Nfft, ...
            m.SINR.DesiredPowerPerReceiveAntenna,unit);
        expected=power.MeasuredLogPower_dB; if ~normalized, expected=expected+30; end
        sameValues(m.("RSRPPerAntenna"+suffix),expected,id,'Original logarithmic RSRP changed.');
        arithmetic=sixgr.phy.refsig.compareCSIRSSINRReference(T,Y,supports{k},f.Nfft,m.SINR,unit);
        sinr=sixgr.phy.refsig.classifyCSIRSSINRModelComparison(arithmetic);
        O=A-T; % All other original linear terms, including common IQ DC.
        terms={T,O,R,X};
        % Reconstruct only the already retained ORIGINAL logical pilot map;
        % do not regenerate CSI-RS from a new configuration or re-estimate H.
        logicalReference=nrResourceGrid(c,resources(k).NumPorts);
        logicalReference(resources(k).Indices)=resources(k).Symbols;
        if isfield(m.SINR.SignalPowerEstimation,'CDMProjectionReceipt')
            recordedCDM=m.SINR.SignalPowerEstimation.CDMProjectionReceipt;
            for name=["NSizeGrid","NStartGrid","SubcarrierSpacing","NSlot","NFrame","SymbolsPerSlot"]
                assert(numericScalarEqual(recordedCDM.CarrierIdentity.(name),c.(name)),id, ...
                    'Original CDM operator must belong to this completed native carrier.');
            end
        end
        matched=sixgr.phy.refsig.compareCSIRSCDMModelReference( ...
            T,O,R,X,Y,logicalReference,supports{k},f.Nfft,m.SINR,unit);
        q=struct('ResourceID',ids(k),'ResourceOrdinal0',k-1,'ResourceSetID',r.ResourceSetID, ...
            'ReferencePort',3000,'TargetPlaneID',string(refs(k).PlaneID), ...
            'OriginalTargetInputSHA256',target.Observation.sampleHash(), ...
            'TargetGridSHA256',numericHash(T),'OriginalCommittedIntervals',{intervals}, ...
            'Port3000SupportSHA256',hash(supports{k}),'PowerComparison',power, ...
            'SINRComparison',sinr,'MatchedCDMModelComparison',matched, ...
            'SignalSupportClosure',energyClosure(terms,Y,supports{k},f.Nfft,unit), ...
            'DisturbanceSupportClosure',energyClosure(terms,Y,sinr.DisturbanceSupport0Based,f.Nfft,unit));
        % Preserve exact -Inf/NaN tokens rather than letting JSON null conflate them.
        q.PowerNumericTokens=struct();
        for name=["ReferenceLogPower_dB","MeasuredLogPower_dB","ReferencePower_dBm", ...
                "MeasuredPower_dBm","PerReceiveColumnError_dB","ReportedError_dB","MeasuredSelectedColumnError_dB"]
            q.PowerNumericTokens.(name)=compose('%.17g',power.(name));
        end
        e.ResourceComparisons{k}=q;
    end
    selected=obs.MeasurementSelectedResourceOrdinal;
    assert(isnumeric(selected)&&isreal(selected)&&isscalar(selected)&&isfinite(selected)&& ...
        selected==fix(selected)&&selected>=1&&selected<=numel(resources),id, ...
        'Retain the original measurement-selected resource; never select by reference power.');
    chosen=e.ResourceComparisons{selected};
    expected=chosen.PowerComparison.MeasuredLogPower_dB; if ~normalized, expected=expected+30; end
    [reported,column]=max(expected,[],'omitnan');
    if isempty(reported)||isnan(reported), reported=NaN; column=NaN; end
    sameValues(obs.("MeasurementRSRP"+suffix),reported,id,'Original selected-resource RSRP changed.');
    sameValues(obs.MeasurementReceiveAntennaIndex1Based,column,id,'Original RSRP column changed.');
    e.SelectedResourceOrdinal1=selected;
    e.OriginalRSRPReceiveColumn1=column;
    e.OriginalSINRReceiveColumn1=chosen.SINRComparison.MeasuredSelectedColumn1;
    e.Stage="completed_optional_all_resource_model_comparison";
    result.CSIRSLinearPortModelComparisonAvailable=true;
    result.CSIRSLinearPortModelComparisonStatus="available_original_fixed_linear_model_not_unique_nonlinear_port_truth";
    result.CSIRSLinearPortModelComparisonUnit=chosen.PowerComparison.LinearPowerUnit;
    result.CSIRSLinearPortModelComparisonReferencePlane=string(element.ReferencePlane);
    result.CSIRSLinearPortModelComparisonResourceCount=numel(resources);
    result.CSIRSLinearPortModelComparisonSelectedResourceID=ids(selected);
    result.CSIRSLinearPortModelComparisonReportedPowerError_dB=chosen.PowerComparison.ReportedError_dB;
    result.CSIRSLinearPortModelComparisonSelectedColumnPowerError_dB=chosen.PowerComparison.MeasuredSelectedColumnError_dB;
    % Unlike SINR estimands retain a log-ratio diagnostic, never an accuracy
    % error. Do not subtract the remaining aggregate: it also contains IQ DC
    % and other signals, not just orthogonal CSI ports.
    for name=["SINREstimandCompatible","SINREstimandCompatibilityStatus", ...
            "SINREstimandCompatibilityReason","ReportedSINRLogRatioDifference_dB", ...
            "SelectedColumnSINRLogRatioDifference_dB"]
        result.("CSIRSLinearPortModelComparison"+name)=chosen.SINRComparison.(name);
    end
    matched=chosen.MatchedCDMModelComparison;
    result.CSIRSLinearPortModelComparisonCDMOperatorMatchedModelAvailable=matched.Available;
    result.CSIRSLinearPortModelComparisonCDMStatus=matched.Status;
    if matched.Available
        for name=["ReportedPowerDifference_dB","SelectedColumnPowerDifference_dB", ...
                "ReportedSINRLogRatioDifference_dB","SelectedColumnSINRLogRatioDifference_dB"]
            result.("CSIRSLinearPortModelComparisonCDM"+name)=matched.(name);
        end
    end
catch cause
    result=emptyResult();
    result.CSIRSLinearPortModelComparisonStatus="unavailable_original_model_comparison_failed";
    result.CSIRSLinearPortModelComparisonErrorIdentifier=string(cause.identifier);
    e.ErrorIdentifier=string(cause.identifier); e.ErrorMessage=string(cause.message);
end
e.Available=result.CSIRSLinearPortModelComparisonAvailable;
e.Status=result.CSIRSLinearPortModelComparisonStatus;
result.CSIRSLinearPortModelComparisonEvidenceJSON=string(jsonencode(sixgr.util.jsonSafeValue(e)));
result.CSIRSLinearPortModelComparisonEvidenceSHA256=sha(result.CSIRSLinearPortModelComparisonEvidenceJSON);
end

function [out,e]=emptyResult()
prefix="CSIRSLinearPortModelComparison"; out=struct();
out.(prefix+"Available")=false;
out.(prefix+"Status")="unavailable_optional_original_model_not_recorded";
out.(prefix+"Source")="post_reception_original_fixed_linear_port_model_comparison";
for name=["EvidenceJSON","EvidenceSHA256","ErrorIdentifier","Unit","ReferencePlane"], out.(prefix+name)=""; end
out.(prefix+"Scope")="fixed_first_order_PA_identity_DAC_model_not_unique_nonlinear_port_truth";
out.(prefix+"ResourceCount")=0;
for name=["SelectedResourceID","ReportedPowerError_dB","SelectedColumnPowerError_dB", ...
        "ReportedSINRError_dB","SelectedColumnSINRError_dB", ...
        "ReportedSINRLogRatioDifference_dB","SelectedColumnSINRLogRatioDifference_dB"]
    out.(prefix+name)=NaN;
end
out.(prefix+"SINREstimandCompatible")=false;
out.(prefix+"SINREstimandCompatibilityStatus")="unavailable_model_comparison_not_evaluated";
out.(prefix+"SINREstimandCompatibilityReason")="No original model comparison was evaluated.";
out.(prefix+"CDMOperatorMatchedModelAvailable")=false;
out.(prefix+"CDMStatus")="unavailable_original_CDM_projection_not_recorded";
out.(prefix+"CDMDenominatorIndependentlyReferenced")=false;
for name=["ReportedPowerDifference_dB","SelectedColumnPowerDifference_dB", ...
        "ReportedSINRLogRatioDifference_dB","SelectedColumnSINRLogRatioDifference_dB"]
    out.(prefix+"CDM"+name)=NaN;
end
for name=["UniqueNonlinearPortAttributionQualified","StandardizedAccuracyQualified","HardwareQualified"]
    out.(prefix+name)=false;
end
e=struct('ContractVersion',"sixgr.csirs.original_linear_port_model_comparison/v2", ...
    'RequirementClass',"IMPLEMENTATION_POLICY",'Stage',"not_attempted", ...
    'Model',"fixed_first_order_PA_identity_DAC", ...
    'TargetDefinition',"original_logical_port3000_homogeneous_widely_linear_reference", ...
    'OtherDefinition',"aggregate_fixed_model_minus_target_includes_common_IQ_DC_and_other_signals", ...
    'ResidualDefinition',"actual_desired_minus_aggregate_includes_PA_DAC_and_model_roundoff_differences", ...
    'ExternalDefinition',"original_composite_minus_original_desired_includes_other_links_and_receiver_noise", ...
    'SINRDefinition',"mean_abs2(target_model_samples)_over_mean_abs2(original_composite_samples_minus_target_model_samples)", ...
    'SINRDisturbanceSupport',"original_dedicated_CSI_IM_if_configured_else_original_port3000_REs", ...
    'AdditionalOFDMDemodulationAttempts',0,'AdditionalOFDMDemodulations',0, ...
    'AdditionalTimingAcquisitions',0,'AdditionalRFExecutions',0,'AdditionalChannelExecutions',0, ...
    'ReferenceUsedByReceiver',false,'UniqueNonlinearPortAttributionQualified',false, ...
    'StandardizedAccuracyQualified',false,'StatisticallyQualified',false,'HardwareQualified',false);
end

function x=plane(item,id,p,isReceive)
if nargin<4, isReceive=true; end
hit=find(string({item.Planes.ReceiverID})==id);
assert(isscalar(hit),'sixgr:truth:CSIRSLinearModelPlane','One original registered plane is required.');
x=item.Planes(hit); b=x.Observation;
assert(isa(b,'sixgr.phy.waveform.WaveformObservationBuffer')&&isscalar(b)&&b.isComplete()&& ...
    b.SampleRateHz==p.SampleRateHz,'sixgr:truth:CSIRSLinearModelPlane','Original complete sample buffer required.');
if isReceive, first=p.ReceiveStartSample; stop=p.ReceiveEndSampleExclusive;
else, first=p.TransmitStartSample; stop=first+p.NumSamples; end
assert(b.StartSample==first&&b.EndSampleExclusive==stop,'sixgr:truth:CSIRSLinearModelPlane', ...
    'Do not substitute another receive or transmit window.');
end

function parent=bindParent(owner,item,p,source,tx,r,refs)
id='sixgr:truth:CSIRSLinearModelParent';
records=owner.CSIRSTransmissions;
hit=find(string({records.ComponentID})==string(item.Context.ComponentID));
assert(isscalar(hit),id,'One actual completed original CSI transmission must own this window.');
x=records(hit); maps=p.Tx.CSIRSRuntimeEvent.ResourceEvents; resources=p.Tx.CSIRSInfo.Resources;
assert(string(x.SignalFamily)=="CSI-RS"&&x.ServingCell==item.Context.ServingCell&& ...
    x.Slot==item.Context.Slot&&x.TransmitStartSample==tx.Observation.StartSample&& ...
    x.EndSampleExclusive==tx.Observation.EndSampleExclusive&&x.CommittedAtSample==x.EndSampleExclusive&& ...
    x.SampleRateHz==p.SampleRateHz&&x.PhysicalConfigurationEpoch==owner.Physical.ConfigurationEpoch&& ...
    string(x.TransmitterID)==string(source.TransmitterID)&& ...
    string(x.TransmitObservationSHA256)==tx.Observation.sampleHash()&& ...
    x.ResourceSetID==r.ResourceSetID&&x.TXAmplitudeScale==p.PowerContext.AmplitudeScale&& ...
    numel(x.ExecutedResourceMaps)==numel(maps)&&numel(maps)==numel(resources),id, ...
    'The model must join actual original TX completion, not merely queue intent.');
for name=["NSizeGrid","NStartGrid","SubcarrierSpacing","NSlot","NFrame"]
    assert(numericScalarEqual(x.CarrierIdentity.(name),p.Carrier.(name)),id, ...
        'The original completed TX owns the native carrier clock and coordinates.');
end
assert(isTextEqual(x.CarrierIdentity.CyclicPrefix,p.Carrier.CyclicPrefix),id,'Original cyclic prefix changed.');
for k=1:numel(maps)
    for name=["ResourceID","LogicalPortCount","WaveformPrecoderDigest", ...
            "WaveformPrecoderMatrix","WaveformIndices","WaveformSymbols"]
        assert(isequaln(x.ExecutedResourceMaps(k).(name),maps(k).(name)),id,'Original executed map changed.');
    end
    assert(isequaln(x.ExecutedResourceMaps(k).LogicalPilotIndices,resources(k).Indices)&& ...
        isequaln(x.ExecutedResourceMaps(k).LogicalPilotSymbols,resources(k).Symbols)&& ...
        refs(k).ResourceSetID==r.ResourceSetID&& ...
        string(refs(k).ParentComponentID)==string(item.Context.ComponentID),id,'Original logical inputs changed.');
end
registry=owner.Physical.readCSIRSPortReferenceRegistrations();
hit=find(arrayfun(@(a)string(a.Parent.Receipt.ComponentID)==string(item.Context.ComponentID)&& ...
    string(a.Parent.Receipt.TransmitterID)==string(source.TransmitterID),registry.Parents));
assert(isscalar(hit),id,'One original installed parent registration is required.');
parent=registry.Parents(hit).Parent; q=parent.Receipt;
assert(isequaln(q,owner.Events.originalEnqueueReceipt(source.TransmitterID,item.Context.ComponentID))&& ...
    q.StartSample==p.TransmitStartSample&&q.EndSampleExclusive==p.TransmitStartSample+p.NumSamples&& ...
    q.SampleRateHz==p.SampleRateHz&&q.NumTransmitAntennas==size(p.TransmitSamples,2)&& ...
    string(q.NumericClass)==string(class(p.TransmitSamples))&& ...
    string(q.OriginalSampleSHA256)==numericHash(p.TransmitSamples)&& ...
    all(string({refs.RegistrationSHA256})==string(parent.RegistrationSHA256)),id, ...
    'Original factor registration must bind the accepted parent and every target.');
for k=1:numel(refs)
    h=find(string({registry.Planes.ID})==string(refs(k).PlaneID));
    assert(isscalar(h)&&string(registry.Planes(h).LinkID)==string(source.LinkID)&& ...
        registry.Planes(h).Component.ResourceID==refs(k).ResourceID&& ...
