function [samples, projection, evidence] = mapDataWaveformToPhysicalElements( ...
        waveform, cfg, phyGrant, role, signal)
%MAPDATAWAVEFORMTOPHYSICALELEMENTS Bind frozen data IQ to physical elements.
%
% A frozen data grant declares whether its generated waveform is in the
% logical NR-port domain or already in the physical antenna-element domain.
% Logical-port IQ is projected exactly once through the configured array.
% Element-domain IQ already contains the hybrid RF/baseband mapping and is
% therefore passed unchanged with an identity stream projection.

arguments
    waveform {mustBeNumeric}
    cfg (1,1) struct
    phyGrant (1,1) struct
    role (1,1) string
    signal (1,1) string
end

if isempty(waveform) || ~ismatrix(waveform) || ...
        any(~isfinite(real(waveform(:)))) || ...
        any(~isfinite(imag(waveform(:))))
    error("sixgr:truth:InvalidPreparedDataWaveform", ...
        "Prepared data IQ must be a nonempty finite sample-by-waveform-column matrix.");
end
if ~logical(sixgr.util.structGet(phyGrant, "IsFrozen", false))
    error("sixgr:truth:SharedDataFrozenGrantRequired", ...
        "Shared data waveform mapping requires an immutable frozen PHYGrant.");
end
sixgr.phy.grant.assertPHYGrantDimensions(phyGrant, ...
    "shared_data_waveform_to_physical_elements", ...
    "Waveform", waveform);

ant = sixgr.util.structGet(phyGrant, "AntennaArchitecture", struct());
if ~(isstruct(ant) && isscalar(ant) && ~isempty(fieldnames(ant)))
    error("sixgr:truth:SharedDataFrozenAntennaArchitectureMissing", ...
        "Frozen shared data PHYGrant lacks AntennaArchitecture authority.");
end

numElements = localPositiveInteger(ant, "NumElements");
numLogicalPorts = localPositiveInteger(ant, "NumLogicalPorts");
numWaveformColumns = localPositiveInteger(ant, "NumWaveformColumns");
elementDomainApplied = logical(sixgr.util.structGet( ...
    ant, "ElementDomainPrecoding", false));
waveformDomain = lower(strtrim(string(sixgr.util.structGet( ...
    ant, "WaveformDomain", ""))));
if ~any(waveformDomain == ["logical_port", "element"])
    error("sixgr:truth:SharedDataWaveformDomainMissing", ...
        "Frozen shared data antenna architecture must declare WaveformDomain as logical_port or element.");
end
if (waveformDomain == "element") ~= elementDomainApplied
    error("sixgr:truth:SharedDataWaveformDomainMismatch", ...
        ["Frozen shared data WaveformDomain='%s' disagrees with " ...
         "ElementDomainPrecoding=%d."], ...
        char(waveformDomain), elementDomainApplied);
end
if size(waveform, 2) ~= numWaveformColumns
    error("sixgr:truth:SharedDataFrozenWaveformColumnMismatch", ...
        ["Prepared %s waveform has %d column(s), but the frozen grant " ...
         "declares %d waveform column(s)."], ...
        upper(char(signal)), size(waveform, 2), numWaveformColumns);
end

if waveformDomain == "element"
    if numWaveformColumns ~= numElements
        error("sixgr:truth:SharedDataElementWaveformShapeMismatch", ...
            ["Element-domain %s waveform declares %d column(s) for %d " ...
             "physical elements."], ...
            upper(char(signal)), numWaveformColumns, numElements);
    end
    projection = eye(numElements, "like", waveform);
    samples = waveform;
    source = "frozen_element_domain_waveform_identity_stream_projection";
else
    if numWaveformColumns ~= numLogicalPorts
        error("sixgr:truth:SharedDataLogicalWaveformShapeMismatch", ...
            ["Logical-port-domain %s waveform declares %d column(s) for " ...
             "%d frozen logical ports."], ...
            upper(char(signal)), numWaveformColumns, numLogicalPorts);
    end
    array = sixgr.rf.AntennaArrayFactory.build(cfg, role, ...
        "signal", signal, "numPorts", numLogicalPorts);
    projection = cast(array.PortToElementMatrix, "like", waveform);
    if ~isequal(size(projection), [numElements numLogicalPorts]) || ...
            any(~isfinite(real(projection(:)))) || ...
            any(~isfinite(imag(projection(:))))
        error("sixgr:truth:SharedDataLogicalProjectionShapeMismatch", ...
            ["Configured %s logical-port projection is %dx%d; expected " ...
             "%dx%d physical-element by logical-port."], ...
            upper(char(signal)), size(projection, 1), size(projection, 2), ...
            numElements, numLogicalPorts);
    end
    gramResidual = norm(double(projection' * projection) - ...
        eye(numLogicalPorts), "fro");
    if ~(isfinite(gramResidual) && gramResidual <= 1e-9 * numLogicalPorts)
        error("sixgr:truth:SharedDataProjectionPowerMismatch", ...
            ["Configured %s logical-port projection is not semi-unitary " ...
             "(Gram residual %.17g)."], ...
            upper(char(signal)), gramResidual);
    end
    samples = waveform * projection.';
    source = "configured_logical_port_to_physical_element_projection";
end

if size(samples, 2) ~= numElements || ...
        any(~isfinite(real(samples(:)))) || ...
        any(~isfinite(imag(samples(:))))
    error("sixgr:truth:SharedDataPhysicalWaveformShapeMismatch", ...
        "Mapped %s IQ must contain one finite column per physical transmit element.", ...
        upper(char(signal)));
end

evidence = struct( ...
    "ContractVersion", "SharedDataWaveformElementMapping/v1", ...
    "Source", source, ...
    "InputWaveformDomain", char(waveformDomain), ...
    "InputWaveformColumns", double(numWaveformColumns), ...
    "NumLogicalPorts", double(numLogicalPorts), ...
    "NumPhysicalElements", double(numElements), ...
    "ProjectionRows", double(size(projection, 1)), ...
    "ProjectionColumns", double(size(projection, 2)), ...
    "ProjectionSHA256", char(sixgr.phy.mimo.MatrixContract.digest( ...
        double(projection))), ...
    "ElementDomainPrecodingAppliedBeforeSharedStream", ...
        logical(elementDomainApplied), ...
    "AdditionalProjectionApplied", waveformDomain == "logical_port");
end

function value = localPositiveInteger(data, fieldName)
value = double(sixgr.util.structGet(data, fieldName, NaN));
if ~(isscalar(value) && isfinite(value) && value >= 1 && value == round(value))
    error("sixgr:truth:SharedDataFrozenAntennaArchitectureInvalid", ...
        "Frozen shared data AntennaArchitecture.%s must be a positive integer.", ...
        char(fieldName));
end
value = round(value);
end
