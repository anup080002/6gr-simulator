function receipt=buildReceivedPUCCHTPCClock(prepared,observation,rx,rxInfo,assignment,observationID,clockEpoch)
% Original selected receiver RE support and applied timing; no TX-field selector.
% Must be called inside the original completeShared receive stack, not by a
% later report adapter. Shared owner ingestion authenticates this receipt.
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && observation.isComplete(), ...
    'sixgr:truth:ReceivedPUCCHControlClock','Require the original completed received capture.');
sixgr.phy.pdcch.validateConnectedAssignment(prepared.ReceiverConfig,assignment);
actual=sixgr.phy.pdcch.materializeConnectedDCI(rx,rxInfo,prepared.ReceiverConfig);
assert(isequaln(actual,assignment),'sixgr:truth:ReceivedPUCCHControlClock', ...
    'Join the original selected receiver bits/context, not any syntactically valid assignment.');
assert(isequal(rx.Ok,true) && rx.ErrFlag==0 && ...
    string(rx.DCISelectionSource)=="receiver_installed_context_crc_and_semantic_parse" && ...
    assignment.Direction=="DL" && any(string(assignment.DCIFormat)==["1_0","1_1"]), ...
    'sixgr:truth:ReceivedPUCCHControlClock','Only the actual accepted selected DL hypothesis supplies TPC timing.');
used=[double(rx.MonitoredDataREIndices(:));double(rx.MonitoredDMRSREIndices(:))];
K=size(rx.RxGrid,1); L=double(rx.ReferenceGridSymbolsPerSlot);
assert(L==14 && ~isempty(used) && all(isfinite(used)&used>=1&used==fix(used)) && ...
    observation.SampleRateHz==prepared.SampleRateHz, ...
    'sixgr:truth:ReceivedPUCCHControlClock','Retain the original native normal-CP receiver support.');
symbols=unique(floor(mod(used-1,K*L)/K));
carrier=sixgr.phy.grid.makeCarrier(prepared.ReceiverConfig);
info=prepared.TxInfo.OFDM;
assert(info.SampleRate==observation.SampleRateHz && ...
    numel(info.SymbolLengths)==14*double(carrier.SlotsPerSubframe), ...
    'sixgr:truth:ReceivedPUCCHControlClock','Original OFDM clock must match actual received sampling.');
lengths=reshape(double(info.SymbolLengths),14,[]);
lengths=lengths(:,mod(double(carrier.NSlot),double(carrier.SlotsPerSubframe))+1);
correction=double(rx.AppliedTimingCorrection_samples);
assert(isscalar(correction)&&isfinite(correction)&&correction>=0&&correction==fix(correction), ...
    'sixgr:truth:ReceivedPUCCHControlClock','Do not replace original applied receive timing.');
first=observation.StartSample+correction+sum(lengths(1:min(symbols)));
stop=observation.StartSample+correction+sum(lengths(1:max(symbols)+1));
assert(first>=observation.StartSample && stop<=observation.EndSampleExclusive && stop>first, ...
    'sixgr:truth:ReceivedPUCCHControlClock','Entire selected control support must have arrived.');
timing=struct('SelectedREIndices',used,'Symbols0Based',symbols,'AppliedTimingCorrection_samples',correction, ...
    'ObservationSHA256',observation.sampleHash(),'FirstSample',first,'EndSampleExclusive',stop, ...
    'NativeSymbolLengths',lengths,'AssignmentDigest',assignment.AssignmentDigest);
receipt=struct('ObservationID',string(observationID),'AssignmentDigest',string(assignment.AssignmentDigest), ...
    'TimingDigest',string(sixgr.util.sha256Hex(char(jsonencode(timing)))), ...
    'PDCCHStartSymbolBoundary',14*double(assignment.ControlAbsoluteSlot)+min(symbols), ...
    'PDCCHEndSymbolBoundary',14*double(assignment.ControlAbsoluteSlot)+max(symbols)+1, ...
    'PDCCHStartSample',first,'PDCCHEndSampleExclusive',stop, ...
    'AvailableAtSample',observation.EndSampleExclusive,'SampleRateHz',observation.SampleRateHz, ...
    'ClockEpoch',clockEpoch,'SubcarrierSpacingKHz',double(carrier.SubcarrierSpacing), ...
    'ReceiverAccepted',true,'ReceiverSelectionSource',string(rx.DCISelectionSource), ...
    'OriginalTimingEvidence',timing);
end
