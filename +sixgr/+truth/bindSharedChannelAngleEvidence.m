function [T,context] = bindSharedChannelAngleEvidence(T,manifest)
%BINDSHAREDCHANNELANGLEEVIDENCE Project executed model angles, not estimates.
% Call after practical reception, with the SAME manifest produced by
% exportSharedChannelObservation. No channel rerun, YAML lookup, angular
% averaging, or receiver input is permitted here. Inspect every segment.
% nrCDLChannel.info returns cluster/path angles of the executed TR 38.901
% model (7.7.1); these are NOT an AoA/AoD estimator's measured output.
% https://www.mathworks.com/help/5g/ref/nrcdlchannel.info.html
arguments
    T table
    manifest (1,1) struct
end
id='sixgr:truth:InvalidSharedChannelAngleEvidence';
assert(height(T)==1,id,'Bind one completed receiver trial.');
required={'Contract','Segments','Source','ReceiverEstimatorInput', ...
    'ObservationStartSample','ObservationEndSampleExclusive','SampleRateHz','InactiveIntervals'};
assert(all(isfield(manifest,required)),id,'The exact channel manifest is incomplete.');
assert(any(string(manifest.Contract)==["actual_shared_channel_observation/v1", ...
    "actual_shared_channel_observation/v2"]),id,'Require an executed channel manifest.');
assert(isfield(manifest,'Segments') && isstruct(manifest.Segments) && ...
    ~isempty(manifest.Segments),id,'Every actual channel segment is required.');
assert(islogical(manifest.ReceiverEstimatorInput) && ...
    isscalar(manifest.ReceiverEstimatorInput) && ~manifest.ReceiverEstimatorInput, ...
    id,'Model angles are post-reception evidence, never estimator inputs.');
assert(ismember('ChannelObservationManifestJSON',T.Properties.VariableNames) && ...
    isequal(string(T.ChannelObservationManifestJSON),string(jsonencode(manifest))), ...
    id,'Bind the exact manifest retained by this completed trial.');
assert(ismember('ChannelObservationManifestSHA256',T.Properties.VariableNames) && ...
    string(T.ChannelObservationManifestSHA256)== ...
    sixgr.phy.waveform.WaveformHash.bytes(T.ChannelObservationManifestJSON), ...
    id,'The retained manifest hash must match its content.');
assert(any(localText(manifest.Source,id)==["same_executed_NR_channel_path_gains_and_filters", ...
    "executed_identity_AWGN_operator","executed_fixed_matrix_AWGN_operator", ...
    "executed_piecewise_matrix_AWGN_operator"]), ...
    id,'No proxy or reconstructed geometry may supply applied channel angles.');
start=localSample(manifest.ObservationStartSample,id);
finish=localSample(manifest.ObservationEndSampleExclusive,id);
assert(finish>start,id,'The observation must have positive sample coverage.');
assert(isnumeric(manifest.SampleRateHz) && isreal(manifest.SampleRateHz) && ...
    isscalar(manifest.SampleRateHz) && isfinite(manifest.SampleRateHz) && ...
    manifest.SampleRateHz>0,id,'Require the executed sample rate.');
segments=manifest.Segments(:);
n=numel(segments); bounds=zeros(n,2); available=false(n,1);
records=cell(n,1); counts=zeros(n,1);
angleNames=["AoD","AoA","ZoD","ZoA"];
required={'SegmentIndex','StartSample','EndSampleExclusive','ExecutionStartSample', ...
    'ExecutionEndSampleExclusive','PathGainDimensions','RuntimeChannelPathDelays_sJSON', ...
    'RuntimeChannelAngleEvidenceAvailable','RuntimeChannelAngleEvidenceSource', ...
    'RuntimeChannelAngleCoordinateFrame','ChannelModelApplied','ChannelFadingObjectClass', ...
    'RuntimeChannelTransmitAndReceiveSwapped','RuntimeChannelAnglesAoD_degJSON', ...
    'RuntimeChannelAnglesAoA_degJSON','RuntimeChannelAnglesZoD_degJSON','RuntimeChannelAnglesZoA_degJSON'};
assert(all(isfield(segments,required)),id,'Every segment needs complete angle provenance.');
for k=1:n
    s=segments(k);
    assert(isequal(double(s.SegmentIndex),double(k)),id, ...
        'Segment identity/order must not change during primary-row binding.');
    bounds(k,:)=[localSample(s.StartSample,id) localSample(s.EndSampleExclusive,id)];
    execution=[localSample(s.ExecutionStartSample,id) localSample(s.ExecutionEndSampleExclusive,id)];
    assert(bounds(k,2)>bounds(k,1) && bounds(k,1)>=start && bounds(k,2)<=finish && ...
        execution(1)<=bounds(k,1) && execution(2)>=bounds(k,2),id, ...
        'Angles must be bound to their actual coefficient execution interval.');
    dimensions=localVector(s.PathGainDimensions,id);
    assert(numel(dimensions)==4 && all(dimensions>=1) && ...
        all(dimensions==fix(dimensions)) && dimensions(1)==diff(bounds(k,:)),id, ...
        'The coefficient path axis and cropped sample interval must match.');
    counts(k)=dimensions(2);
    delays=localVector(s.RuntimeChannelPathDelays_sJSON,id);
    assert(numel(delays)==counts(k) && all(delays>=0),id, ...
        'Retain the executed delay axis; do not sort cluster paths by angle.');
    available(k)=localFlag(s.RuntimeChannelAngleEvidenceAvailable,id);
    source=localText(s.RuntimeChannelAngleEvidenceSource,id);
    frame=localText(s.RuntimeChannelAngleCoordinateFrame,id);
    model=localText(s.ChannelModelApplied,id);
    objectClass=localText(s.ChannelFadingObjectClass,id);
    assert(objectClass~="nrCDLChannel" || available(k),id, ...
        'Missing CDL info is a producer defect; do not turn it into an optional absent measurement.');
    record=struct('SegmentIndex',k,'StartSample',bounds(k,1), ...
        'EndSampleExclusive',bounds(k,2),'ExecutionStartSample',execution(1), ...
        'ExecutionEndSampleExclusive',execution(2),'Available',available(k), ...
        'ChannelModelApplied',model,'ChannelFadingObjectClass',objectClass, ...
        'PathCount',counts(k),'PathDelays_s',delays, ...
        'TransmitAndReceiveSwapped',localFlag(s.RuntimeChannelTransmitAndReceiveSwapped,id), ...
        'CoordinateFrame',frame,'Source',source);
    for name=angleNames
        value=localVector(s.("RuntimeChannelAngles"+name+"_degJSON"),id);
        assert((available(k) && numel(value)==counts(k)) || ...
            (~available(k) && isempty(value)),id, ...
            'All four angle vectors must describe every actual path or remain explicitly absent.');
        if startsWith(name,'Zo')
            assert(all(value>=0 & value<=180),id,'Zenith is measured from +z, in [0,180] degrees.');
        end
        record.("Angles"+name+"_deg")=value;
    end
    if available(k)
        assert(string(manifest.Source)=="same_executed_NR_channel_path_gains_and_filters" && ...
            objectClass=="nrCDLChannel" && startsWith(model,"CDL-") && ...
            frame=="3gpp_tr38901_global_coordinate_system" && ...
            source=="info_on_same_executed_runtime_channel_object",id, ...
            'Applied CDL angles must originate from the executed object, not geometry or a receiver estimate.');
    else
        assert(strlength(source)==0 && strlength(frame)==0,id, ...
            'Absent angle vectors cannot carry a claimed applied angular reference.');
    end
    records{k}=record;
end
assert(all(bounds(2:end,1)>=bounds(1:end-1,2)),id,'Coefficient segments must be ordered and non-overlapping.');
inactive=manifest.InactiveIntervals;
assert(isnumeric(inactive) && isreal(inactive) && (isempty(inactive) || ...
    (ismatrix(inactive) && size(inactive,2)==2 && all(isfinite(inactive),'all') && ...
    all(inactive==fix(inactive),'all') && all(inactive(:,2)>inactive(:,1)))), ...
    id,'Inactive intervals require explicit sample bounds.');
coverage=sortrows([bounds;reshape(inactive,[],2)],1);
assert(coverage(1,1)==start && coverage(end,2)==finish && ...
    all(coverage(2:end,1)==coverage(1:end-1,2)),id, ...
    'Active and inactive intervals must cover the observation exactly once.');
allAvailable=all(available); invariant=allAvailable;
for k=2:n
    for name=["PathDelays_s","CoordinateFrame","Source","TransmitAndReceiveSwapped", ...
            "AnglesAoD_deg","AnglesAoA_deg","AnglesZoD_deg","AnglesZoA_deg"]
        invariant=invariant && isequal(records{k}.(name),records{1}.(name));
    end
end
status="not_available_from_executed_channel_object";
if any(available), status="partial_applied_model_angles_by_segment"; end
if allAvailable, status="available_time_varying_applied_model_angles"; end
if invariant, status="available_invariant_applied_model_angles"; end
context=struct('RuntimeChannelAngleEvidenceAvailable',invariant, ...
    'RuntimeChannelAngleSegmentEvidenceAvailable',allAvailable, ...
    'RuntimeChannelAngleVectorsInvariant',invariant, ...
    'RuntimeChannelAngleEvidenceStatus',status, ...
    'RuntimeChannelAngleEvidenceSource',"",'RuntimeChannelAngleCoordinateFrame',"", ...
    'RuntimeChannelAnglePathCount',NaN,'RuntimeChannelAngleSegmentCount',n, ...
    'RuntimeChannelAngleValueRole',"executed_channel_model_parameter_not_receiver_estimate", ...
    'RuntimeChannelAngleSegmentsJSON',string(jsonencode(vertcat(records{:}))));
if ~any(available), context.RuntimeChannelAnglePathCount=0; end
if allAvailable && all(counts==counts(1))
    context.RuntimeChannelAnglePathCount=counts(1);
end
for name=angleNames
    value=[];
    if invariant, value=records{1}.("Angles"+name+"_deg"); end
    context.("RuntimeChannelAngles"+name+"_deg")=value;
end
if invariant
    context.RuntimeChannelAngleEvidenceSource=records{1}.Source;
    context.RuntimeChannelAngleCoordinateFrame=records{1}.CoordinateFrame;
end
for name=string(fieldnames(context)).'
    value=context.(name);
    if endsWith(name,'_deg')
        T.(name+"JSON")=string(jsonencode(value));
    else
        T.(name)=value;
    end
end
end

function value=localSample(value,id)
assert(isnumeric(value) && isreal(value) && isscalar(value) && isfinite(value) && ...
    value>=0 && value==fix(value) && value<=flintmax,id,'Require exact nonnegative sample indices.');
value=double(value);
end

function value=localText(value,id)
assert(isstring(value) || (ischar(value) && (isrow(value) || isempty(value))), ...
    id,'Metadata must be scalar text.');
value=string(value);
assert(isscalar(value) && ~ismissing(value),id,'Metadata must not be missing.');
end

function value=localVector(raw,id)
raw=localText(raw,id);
try
    value=jsondecode(raw);
catch cause
    error(id,'Invalid numeric vector JSON: %s',cause.message);
end
assert(isnumeric(value) && isreal(value) && (isempty(value) || isvector(value)) && ...
    all(isfinite(value),'all'),id,'Require a finite numeric vector, not a scalar surrogate.');
value=reshape(double(value),1,[]);
end

function value=localFlag(value,id)
assert((islogical(value) || isnumeric(value)) && isreal(value) && isscalar(value) && ...
    isfinite(value) && any(value==[0 1]),id,'Require an explicit application boolean.');
value=logical(value);
end
