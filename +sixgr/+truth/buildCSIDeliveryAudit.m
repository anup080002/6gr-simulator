function token=buildCSIDeliveryAudit(received,prepared,receipt,receiverRequest)
%BUILDCSIDELIVERYAUDIT Private post-reception TX/RX evidence, never RX input.
% PUCCH only: the current runtime binds one configured CSI report per UCI.
% The receipt must come from SharedPUCCHTXLedger, not a planned transmission.
% TX operands come from the emitted transmitter's selected serialization;
% UE recommendations and UEReferenceRecordJSON are deliberately not read.
arguments
    received (1,1) struct
    prepared (1,1) sixgr.link.PreparedUplinkControlTransmission
    receipt (1,1) struct
    receiverRequest (1,1) struct
end
token="";
assert(prepared.Channel=="PUCCH" && string(received.CSIUCIChannel)=="PUCCH", ...
    'sixgr:truth:CSIDeliveryTransport','Only executed PUCCH delivery is supported by this adapter.');
identity=sixgr.truth.preparedPUCCHTransmissionIdentity( ...
    prepared,received.UEIndex,received.ObservationID);
assert(all(isfield(receipt,{'Identity','FirstActiveSample','CommittedAtSample','Source'})) && ...
    isequaln(receipt.Identity,identity) && ...
    string(receipt.Source)=="actual_shared_PUCCH_transmission_started_not_receiver_outcome", ...
    'sixgr:truth:CSIDeliveryEmissionIdentity','Use the exact committed shared PUCCH TX ledger entry.');
assert(receipt.FirstActiveSample>=identity.StartSample && ...
    receipt.FirstActiveSample<identity.EndSampleExclusive && ...
    receipt.CommittedAtSample==receipt.FirstActiveSample+1 && ...
    receipt.CommittedAtSample<=received.AvailableAtSample && ...
    identity.EndSampleExclusive<=received.AvailableAtSample && ...
    received.ObservationStartSample<received.ObservationEndSampleExclusive && ...
    received.ObservationEndSampleExclusive<=received.AvailableAtSample && ...
    received.ReceiverClockEpoch==identity.RFConfigurationEpoch && ...
    received.ObservationSampleRateHz==identity.SampleRateHz && ...
    string(received.ReceiverClockDomain)=="shared_receiver_sample_clock/v1", ...
    'sixgr:truth:CSIDeliveryEmissionClock','The committed emission and received report must share the executed clock.');
tx=prepared.Tx; assignment=prepared.RequestBinding.Assignment;
assert(isequaln(tx.Assignment,assignment) && ...
    tx.Report.Digest==prepared.RequestBinding.Report.Digest && ...
    tx.AssignmentDigest==identity.AssignmentDigest && tx.ReportDigest==identity.ReportDigest && ...
    assignment.Data.RNTI==received.RNTI && assignment.Data.ServingCell==received.ServingCell && ...
    assignment.DueSlot==received.DueSlot && tx.TransmissionPresent, ...
    'sixgr:truth:CSIDeliveryTXBinding','Retain the actual emitted assignment/report and receive occasion.');
selection=assignment.Data.CSISelection;
assert(string(selection.Authority)=="UE_transmit_selection_not_receiver_evidence", ...
    'sixgr:truth:CSIDeliverySelection','Retain the original transmitter CSI selection authority.');
sixgr.phy.pucch.validateTransmitUCILayout(tx.Report,tx.Serialization);
layout=tx.Serialization.Layout;
bits=[tx.Serialization.Sequence1.Bits;tx.Serialization.Sequence2.Bits];
assert(isequal(bits,layout.BitValue) && tx.SerializationDigest==tx.Serialization.Digest, ...
    'sixgr:truth:CSIDeliverySerialization','Retain the actual transmitter serialization, including ownership.');
selected=tx.Report.Data.CSIReports;
if isa(selected,'sixgr.phy.pucch.CSIReportState'), selected=selected.Data; end
if isempty(selection.RequestedReportIDs)
    % The independent gNB can expect CSI while the UE has no eligible report.
    % A real HARQ/SR-only waveform must not crash post-reception publication,
    % nor become evidence of CSI emission. Keep the received outcome intact.
    assert(isempty(selection.TransmittedReportIDs) && isempty(selection.OmittedReportIDs) && ...
        isempty(selected) && ~any(startsWith(string(layout.FieldName),"CSI_")), ...
        'sixgr:truth:CSIDeliverySelection', ...
        'No requested CSI requires no selected report or serialized CSI bits.');
    return;
end
assert(numel(selection.RequestedReportIDs)==1, ...
    'sixgr:truth:CSIDeliveryAmbiguousReport','Multiple requested CSI reports require an explicit report-to-schema mapping.');
localID=selection.RequestedReportIDs(1);
if ~ismember(localID,selection.TransmittedReportIDs)
    assert(ismember(localID,selection.OmittedReportIDs), ...
        'sixgr:truth:CSIDeliverySelection','Unselected CSI must retain its omission disposition.');
    return; % An emitted HARQ waveform is not an emitted CSI report.
end
assert(isequal(selection.TransmittedReportIDs,localID) && isempty(selection.OmittedReportIDs), ...
    'sixgr:truth:CSIDeliverySelection','This adapter requires one unambiguously selected report.');
p1=bits(string(layout.FieldName)=="CSI_"+string(localID)+"_PART1");
p2=bits(string(layout.FieldName)=="CSI_"+string(localID)+"_PART2");
assert(numel(selected)==1 && selected.ReportID==localID && ...
    isequal(p1,int8(selected.Part1Bits(:))) && isequal(p2,int8(selected.Part2Bits(:))) && ...
    ~isempty(p1), 'sixgr:truth:CSIDeliverySerialization', ...
    'Selected CSI and actual serialization must agree; never replace missing bits with recommendations.');
request=prepared.InputConfig.phy.csi.reportConfiguration;
txSchema=sixgr.phy.mimo.CSIReportConfiguration(request,received.CSIConfigurationEpoch);
rxSchema=sixgr.phy.mimo.CSIReportConfiguration(receiverRequest,received.CSIConfigurationEpoch);
assert(txSchema.ReportConfigID==string(received.CSIReportConfigID) && ...
    rxSchema.ReportConfigID==txSchema.ReportConfigID && ...
    txSchema.UCIChannel=="PUCCH" && rxSchema.UCIChannel=="PUCCH", ...
    'sixgr:truth:CSIDeliverySchemaIdentity','Use the frozen transmitter and receiver report configurations.');
txSchema.decode(p1,p2); % Validate emitted bits; do not use producer field values.
audit=struct('Schema',"sixgr.csi_delivery_audit/v1", ...
    'Source',"executed_PUCCH_serialization_posthoc_not_receiver_input", ...
    'Scope',"single_configured_CSI_report_per_PUCCH", ...
    'Identity',struct(),'PopulationIdentity',struct(),'TransmissionIdentity',identity, ...
    'FirstActiveSample',receipt.FirstActiveSample,'CommittedAtSample',receipt.CommittedAtSample, ...
    'LocalCSIReportID',localID,'SelectionReason',string(selection.Reason), ...
    'SerializationDigest',tx.SerializationDigest, ...
    'EmissionEvidence',"committed_TX_start_and_completed_receiver_clock_after_TX_end", ...
    'ReferenceAttributionQualified',false, ...
    'TXSchemaJSON',string(jsonencode(orderfields(request))), ...
    'RXSchemaJSON',string(jsonencode(orderfields(receiverRequest))), ...
    'SpecificationProfile',txSchema.SpecificationProfile, ...
    'SpecificationJSON',string(jsonencode(sixgr.phy.mimo.MIMOSpecificationProfile().asStruct())), ...
    'TXPart1BitsToken',sixgr.runtime.RawCSVArrayCodec.encode(p1), ...
    'TXPart2BitsToken',sixgr.runtime.RawCSVArrayCodec.encode(p2), ...
    'TXPart1BitCount',numel(p1),'TXPart2BitCount',numel(p2));
for field=["Direction","UEIndex","RNTI","ServingCell","ReportIdentity", ...
        "CSIReportConfigID","CSIConfigurationEpoch","CSIReferenceSlot","DueSlot", ...
        "ObservationID","ReceiverClockEpoch","ObservationSampleRateHz", ...
        "ObservationStartSample","ObservationEndSampleExclusive","AvailableAtSample"]
    audit.Identity.(field)=received.(field);
end
% Supplied completion-context metadata is not a claim about the TX sweep
% point. Missing component lifecycle stays absent, never assigned an ID.
for field=["RunID","RunTag","RunFolder","ExecutionID","ConfigHash","ScenarioID", ...
        "RandomSeed","ChannelSeed","SweepPointIndex","ConfiguredSNR_dB", ...
        "PopulationIdentitySource"]
    if ~isfield(received,field), continue; end
    value=received.(field);
    if ((isnumeric(value)||islogical(value)) && isscalar(value) && isfinite(value)) || ...
            ((isstring(value)||ischar(value)) && isscalar(string(value)) && ...
            ~ismissing(string(value)) && strlength(strtrim(string(value)))>0)
        audit.PopulationIdentity.(field)=value;
    end
end
audit.TXSchemaSHA256=sixgr.l2.mac.MACHash.of(audit.TXSchemaJSON);
audit.RXSchemaSHA256=sixgr.l2.mac.MACHash.of(audit.RXSchemaJSON);
audit.AuditSHA256=sixgr.l2.mac.MACHash.of(orderfields(audit));
token=string(jsonencode(audit));
end
