function T=rfChainPowerInterval(replay,endpoint,role,direction,first,stop,fs,ports)
% Compact physical-chain measurements, separate from old scalar RF ledger.
% Never infer radiated TRP/EIRP or watts from normalized/undeclared samples.
prototype=struct('EndpointID',"",'Role',"",'Direction',"", ...
    'StartSample',NaN,'EndSampleExclusive',NaN,'SampleRateHz',NaN, ...
    'PhysicalChainCount',NaN,'SampleCount',NaN,'WaveformAmplitudeUnit',"undeclared", ...
    'InputPerChainMeanSquareJSON',"",'OutputPerChainMeanSquareJSON',"", ...
    'PostPAPerChainMeanSquareJSON',"",'InputTotalMeanSquare',NaN, ...
    'OutputTotalMeanSquare',NaN,'PostPATotalMeanSquare',NaN, ...
    'PostPATotalPower_mW',NaN,'PostPAPerChainPower_dBmJSON',"", ...
    'PostPAStatus',"not_applicable_receiver", ...
    'Population',"all_samples_including_cp_and_idle_not_active_RE_EPRE", ...
    'ReferencePlane',"RF_operator_boundaries_not_TRP_or_directional_EIRP", ...
    'Source',"measured_physical_chain_sample_power");
% MATLAB struct2table on a zero-element struct discards the field classes.
% Construct one typed row first, then retain an empty slice of that table.
T=struct2table(prototype); T=T([],:);
if nargin==0, return; end
% Old receipts remain old evidence. No per-chain split is reconstructed
% from their endpoint average or configured antenna count.
if ~isfield(replay,'RFChainPowerEvidence'), return; end
e=replay.RFChainPowerEvidence;
assert(isstruct(e)&&isscalar(e)&&all(isfield(e,{'Input','Output','PostPA'})), ...
    'sixgr:truth:RFChainPowerEvidence','Require measured RF boundary statistics.');
row=prototype; row.EndpointID=string(endpoint); row.Role=string(role);
row.Direction=string(direction); row.StartSample=first; row.EndSampleExclusive=stop;
row.SampleRateHz=fs; row.PhysicalChainCount=ports; row.SampleCount=stop-first;
row.WaveformAmplitudeUnit=string(sixgr.util.structGet(replay,'WaveformAmplitudeUnit','undeclared'));
assert(isscalar(row.WaveformAmplitudeUnit)&&ismember(row.WaveformAmplitudeUnit, ...
    ["undeclared","sqrt_mW","normalized_complex_baseband"]), ...
    'sixgr:truth:RFChainPowerUnit','Retain the actual declared amplitude unit.');
for item=["Input","Output","PostPA"]
    if item=="PostPA" && row.Role=="RX"
        assert(isempty(e.PostPA),'sixgr:truth:RFChainPowerPlane','RX has no TX PA plane.');
        continue;
    end
    v=e.(item); expectedPlane="rf_"+lower(item);
    if item=="PostPA", expectedPlane="post_tx_pa"; end
    assert(isstruct(v)&&isscalar(v)&&all(isfield(v, ...
        {'Contract','Plane','SampleCount','PhysicalChainCount','MeanSquarePerChain', ...
        'SquaredMagnitudeSumPerChain','TotalMeanSquare','Population','Source'})) && ...
        string(v.Contract)=="physical_chain_sample_power/v1" && string(v.Plane)==expectedPlane && ...
        v.SampleCount==row.SampleCount && v.PhysicalChainCount==ports && ...
        string(v.Population)=="all_supplied_samples_including_cp_and_idle_not_active_RE_EPRE" && ...
        string(v.Source)=="actual_RF_operator_boundary_samples", ...
        'sixgr:truth:RFChainPowerEvidence','Chain measurements must match the executed interval and plane.');
    p=double(v.MeanSquarePerChain(:).'); q=double(v.SquaredMagnitudeSumPerChain(:).');
    assert(numel(p)==ports&&numel(q)==ports && all(isfinite(p)&p>=0) && ...
        all(isfinite(q)&q>=0) && isscalar(v.TotalMeanSquare) && isfinite(v.TotalMeanSquare) && ...
        all(abs(q-p*row.SampleCount)<=localTolerance(max(q))) && ...
        abs(sum(p)-v.TotalMeanSquare)<=localTolerance(sum(p)), ...
        'sixgr:truth:RFChainPowerClosure','Per-chain measurements must sum to the same-plane endpoint power.');
    row.(item+"PerChainMeanSquareJSON")=string(jsonencode(p));
    row.(item+"TotalMeanSquare")=double(v.TotalMeanSquare);
    if item=="PostPA"
        row.PostPAStatus="measured_after_PA_stage_including_disabled_identity";
        if row.WaveformAmplitudeUnit=="sqrt_mW"
            row.PostPATotalPower_mW=v.TotalMeanSquare;
            % Zero power has -Inf dBm, serialized as null; its exact zero
            % remains in the linear per-chain array. Never use an epsilon.
            row.PostPAPerChainPower_dBmJSON=string(jsonencode(10*log10(p)));
        end
    end
end
T=struct2table(row);
end
function t=localTolerance(scale)
% Numerical closure, not a performance threshold or absolute mW floor.
t=max(1e-11*scale,64*eps(scale));
end
