function [T,metadata]=buildRAReceiverRFObservation(item,ra,servingCell,snr,availableAt)
% Actual RF executions for one RA receive window, including silent/failing
% monitoring. This is neither a decoded message nor a successful attachment.
validateattributes(servingCell,{'numeric'},{'scalar','integer','positive','finite'});
validateattributes(item.UE,{'numeric'},{'scalar','integer','positive','finite'});
validateattributes(availableAt,{'numeric'},{'scalar','integer','nonnegative','finite'});
validateattributes(snr,{'numeric'},{'scalar','real','finite'});
assert(all(isfield(ra,{'RunId','UEId','AttemptId'})), ...
    'sixgr:truth:MissingRARFIdentity','Keep the receiver attempt identity.');
assert(isfield(item,'ID') && isscalar(string(item.ID)) && ...
    ~ismissing(string(item.ID)) && strlength(strtrim(string(item.ID)))>0, ...
    'sixgr:truth:MissingRARFObservationIdentity', ...
    'Completion must preserve its registered physical observation ID; do not reconstruct it from slot or payload.');
kind=string(item.Kind);
if kind=="RA"
    prepared=item.Context.Prepared;
    stage=string(prepared.StageName); direction=string(prepared.Direction);
    slot=double(prepared.AbsoluteSlot);
    if any(stage==["Msg1","Msg3","RRCSetupComplete"]), expected="UL";
    elseif any(stage==["Msg2","Msg4"]), expected="DL";
    else, error('sixgr:truth:InvalidRARFStage','Unknown physical RA stage.'); end
    assert(direction==expected,'sixgr:truth:RARFDirectionMismatch', ...
        'The physical stage and endpoint direction must agree.');
elseif any(kind==["RAR","Contention"])
    stage=kind+"Monitoring"; direction="DL";
    slot=double(item.Context.AbsoluteSlot);
else
    error('sixgr:truth:NonphysicalRARFEvent', ...
        'Timer expiry/start events have no RF observation to publish.');
end
validateattributes(slot,{'double'},{'scalar','integer','nonnegative','finite'});
tx="gnb_"+servingCell; rx="ue_"+item.UE+"_rx";
if direction=="UL", tx="ue_"+item.UE; rx="gnb_"+servingCell+"_rx"; end
ids=string({item.Planes.ReceiverID});
assert(sum(ids==tx+":tx")==1 && sum(ids==rx+":pre_rf")==1 && ...
    sum(ids==rx+":post_rf")==1,'sixgr:truth:RARFEndpointMismatch', ...
    'Do not borrow RF execution from another UE, serving cell or direction.');
observation=item.Planes(ids==rx+":post_rf").Observation;
assert(availableAt>=observation.EndSampleExclusive, ...
    'sixgr:truth:RARFPublicationBeforeReception','Complete the observation before publication.');
T=table(string(ra.RunId),double(ra.UEId),double(item.UE),double(servingCell), ...
    double(ra.AttemptId),string(item.ID),kind,stage,direction,slot,slot+1, ...
    double(snr),tx,rx,observation.StartSample,observation.EndSampleExclusive, ...
    observation.SampleRateHz,double(availableAt), ...
    "actual_receive_window_RF_execution_not_decode_or_attachment_result", ...
    'VariableNames',{'RunId','UEId','RuntimeUEIndex','ServingCell','AttemptId', ...
    'ObservationID','ObservationKind','StageName','Direction','AbsoluteSlot0','RuntimeSlot', ...
    'ConfiguredSNR_dB','TransmitterID','ReceiverID','ObservationStartSample', ...
    'ObservationEndSampleExclusive','ObservationSampleRateHz','ResultAvailableAtSample','EvidenceScope'});
metadata=sixgr.truth.bindSharedRFExecutionEvidence( ...
    table(true,'VariableNames',{'ObservationPresent'}),item.Planes,true);
metadata.ObservationPresent=[];
T=[T metadata];
end
