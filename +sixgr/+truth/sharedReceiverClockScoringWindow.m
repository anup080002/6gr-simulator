function [samples,evidence]=sharedReceiverClockScoringWindow(reference,source,replay,first,count)
%SHAREDRECEIVERCLOCKSCORINGWINDOW Exact retained pre-RX IQ on an RX delay clock.
% Post-reception scoring only. For recorded integer delay d, RX sample n
% corresponds to desired-link sample n-d. TX RF/channel delay is already in
% the retained reference and MUST NOT be reapplied. No RF/channel execution,
% padding, interpolation, estimated delay, gain fit or receiver input here.
arguments
    reference (1,1) sixgr.phy.waveform.WaveformObservationBuffer
    source (1,1) struct
    replay (1,1) struct
    first (1,1) double {mustBeFinite,mustBeInteger,mustBeNonnegative}
    count (1,1) double {mustBeFinite,mustBeInteger,mustBePositive}
end
assert(reference.isComplete() && ...
    all(isfield(source,{'Source','ReceiverID','TransmitterID', ...
    'ReceiverEstimatorInput','AdditionalChannelExecutions','AdditionalRFExecutions'})) && ...
    string(source.Source)=="actual_executed_link_contribution" && ...
    isequal(source.ReceiverEstimatorInput,false) && ...
    source.AdditionalChannelExecutions==0 && source.AdditionalRFExecutions==0 && ...
    ~sixgr.util.structGet(source,'ReceiverTimingIncluded',false), ...
    'sixgr:truth:InvalidReceiverClockScoringSource', ...
    'Use the complete, unshifted executed desired-link reference for scoring only.');
assert(all(isfield(replay,{'ReceiverID','TransmitterID','ReceiveStreamExecutionSegments'})) && ...
    string(replay.ReceiverID)==string(source.ReceiverID) && ...
    string(replay.TransmitterID)==string(source.TransmitterID), ...
    'sixgr:truth:ReceiverClockScoringIdentityMismatch', ...
    'Scoring reference and receiver execution must identify the same physical link.');
segments=replay.ReceiveStreamExecutionSegments;
assert(iscell(segments) && ~isempty(segments), ...
    'sixgr:truth:MissingReceiverClockExecution', ...
    'Scoring needs actual RX endpoint execution, not a configured or TX+RX delay.');
last=first+count;
next=first;
delay=NaN;
used=0;
for k=1:numel(segments)
    segment=segments{k};
    assert(isstruct(segment) && isscalar(segment) && ...
        all(isfield(segment,{'StartSample','EndSampleExclusive','Execution'})), ...
        'sixgr:truth:InvalidReceiverClockSegment','Retain absolute execution segment bounds.');
    a=double(segment.StartSample); b=double(segment.EndSampleExclusive);
    validateattributes([a b],{'double'},{'real','finite','integer','nonnegative'});
    assert(b>a,'sixgr:truth:InvalidReceiverClockSegment','Execution intervals must be nonempty.');
    if b<=first || a>=last, continue; end
    a=max(a,first); b=min(b,last);
    assert(a==next && isfield(segment.Execution,'RX'), ...
        'sixgr:truth:IncompleteReceiverClockExecution', ...
        'Every requested receiver sample requires exactly one ordered execution interval.');
    endpoints=segment.Execution.RX;
    assert(isstruct(endpoints) && isfield(endpoints,'ID') && isfield(endpoints,'Replay'), ...
        'sixgr:truth:MissingReceiverClockExecution','Retain executed receiver endpoint identities.');
    endpoint=endpoints(string({endpoints.ID})==string(replay.ReceiverID));
    assert(isscalar(endpoint) && isfield(endpoint.Replay,'InjectedTimingOffset_samples'), ...
        'sixgr:truth:MissingReceiverClockExecution', ...
        'One matching RX endpoint must own the recorded delay.');
    current=double(endpoint.Replay.InjectedTimingOffset_samples);
    assert(isscalar(current) && isreal(current) && isfinite(current) && ...
        current>=0 && current==fix(current), ...
        'sixgr:truth:UnsupportedReceiverScoringDelay', ...
        'Fractional/negative RX delay needs its executed filter history; do not approximate it.');
    if used==0, delay=current; end
    assert(current==delay,'sixgr:truth:TimeVaryingReceiverScoringDelay', ...
        'A varying delay requires its executed filter-state transition, not one fitted shift.');
    used=used+1; next=b;
end
assert(used>0 && next==last, ...
    'sixgr:truth:IncompleteReceiverClockExecution', ...
    'Actual RX execution must cover the complete requested scoring window.');
sourceFirst=first-delay;
sourceLast=last-delay;
assert(sourceFirst>=reference.StartSample && sourceLast<=reference.EndSampleExclusive, ...
    'sixgr:truth:MissingReceiverScoringHistory', ...
    'Required desired-link samples [%g,%g) are not retained in [%g,%g); padding is forbidden.', ...
    sourceFirst,sourceLast,reference.StartSample,reference.EndSampleExclusive);
wave=reference.readComplete();
indices=(sourceFirst-reference.StartSample+1):(sourceLast-reference.StartSample);
samples=wave(indices,:);
evidence=source;
evidence.TimingAlignmentSource="recorded_RX_endpoint_integer_delay_exact_retained_sample_selection";
evidence.ReferencePlane="executed_desired_link_on_RX_timing_clock_before_noise_and_other_RX_RF";
evidence.RecordedReceiverTimingOffset_samples=delay;
evidence.ReceiverTimingIncluded=true;
evidence.ReceiverCFOIncluded=false;
evidence.TXTimingReapplied=false;
evidence.GainOrPhaseFitted=false;
evidence.ReceiveStartSample=first;
evidence.ReceiveEndSampleExclusive=last;
evidence.ReferenceStartSample=sourceFirst;
evidence.ReferenceEndSampleExclusive=sourceLast;
evidence.SampleRateHz=reference.SampleRateHz;
end
