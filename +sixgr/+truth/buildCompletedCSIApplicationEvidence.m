function evidence=buildCompletedCSIApplicationEvidence(state,item,control,res)
%BUILDCOMPLETEDCSIAPPLICATIONEVIDENCE Post-commit DL application evidence.
% Called only after the actual shared completeSlot has committed reception.
% This reads the original owner, admitted report, accepted control record,
% frozen preparation, completed sample buffers and RX commit. It does not
% decode, schedule, look up current configuration, or change those operands.
% Successful PDCCH authority is the retained receiver-owned control record,
% NOT a new decoder replay. Every native resource's PRG/symbol page must
% match the retained frozen matrix; page counts are not averaged or limited.
% Component observations without lifecycle identity remain component-only.
id='sixgr:truth:CompletedCSIOwnerRequired';
assert(nargin==4 && isstruct(state) && isscalar(state) && ...
    isfield(state,'SharedWaveformStream') && ...
    isa(state.SharedWaveformStream,'sixgr.truth.CoupledWaveformStream'),id, ...
    'Use the original completed shared physical owner, not asserted receipt flags.');
owner=state.SharedWaveformStream;
assert(isscalar(owner) && ~owner.Events.Faulted && ~owner.Physical.Faulted && ...
    owner.Events.NextSampleIndex==owner.Physical.NextSampleIndex, ...
    'sixgr:truth:CompletedCSIClockMismatch','Require one nonfaulted physical/event clock.');
assert(isstruct(item) && isscalar(item) && all(isfield(item,{'ID','Kind','UE','Context','Planes'})) && ...
    string(item.Kind)=="PDSCH" && isstruct(item.Context) && ...
    all(isfield(item.Context,{'Prepared','TransmissionIdentity','WaveformToElementMatrix'})) && ...
    isa(item.Context.Prepared,'sixgr.link.PreparedDataTransmission'), ...
    'sixgr:truth:CompletedCSIItemRequired','Retain the actual PDSCH completion and immutable preparation.');
p=item.Context.Prepared; grant=p.RequestBinding.Grant; phy=p.RequestBinding.PHYGrant;
identity=sixgr.truth.preparedDataTransmissionIdentity(p,item.UE);
logicalGrantID=string(sixgr.util.structGet(grant,'GrantContextId',""));
assert(localText(logicalGrantID),'sixgr:truth:CompletedCSIIdentityMismatch', ...
    'Retain the original prepared logical grant identity separately from the frozen PHY identity.');
assert(p.Direction=="DL" && isequaln(identity,item.Context.TransmissionIdentity) && ...
    phy.IsFrozen && p.SampleRateHz==owner.SampleRateHz && ...
    localText(item.ID) && isfield(grant,'ServingCell'), ...
    'sixgr:truth:CompletedCSIIdentityMismatch','Completion and frozen TX identity must agree.');

% This private owner ledger proves a start; the remaining checks prove end.
records=owner.DataTransmissions;
hit=find(arrayfun(@(r)r.Identity.TransmissionID==identity.TransmissionID,records));
ledger=sixgr.util.structGet(state,'SharedDataTXLedger',{});
committed=find(cellfun(@(r)r.Identity.TransmissionID==identity.TransmissionID,ledger));
assert(isscalar(hit) && isscalar(committed), ...
    'sixgr:truth:CompletedCSITXReceiptRequired','Require unique physical-owner and MAC TX receipts.');
receipt=records(hit); mac=ledger{committed};
assert(isequaln(receipt.Identity,identity) && isequaln(mac.Identity,identity) && ...
    receipt.FirstActiveSample>=identity.StartSample && receipt.FirstActiveSample<identity.EndSampleExclusive && ...
    receipt.CommittedAtSample==receipt.FirstActiveSample+1 && ...
    mac.FirstActiveSample==receipt.FirstActiveSample && mac.CommittedAtSample==receipt.CommittedAtSample && ...
    isequaln(receipt.WaveformToElementMatrix,item.Context.WaveformToElementMatrix) && ...
    string(sixgr.util.structGet(mac.Grant,'GrantContextId',""))==logicalGrantID && ...
    isequaln(mac.Grant.PHYGrant.PrecodingState,phy.PrecodingState) && ...
    isequal(mac.TransportBlockBits,int8(p.Tx.TransportBlock(:))) && ...
    numel(mac.TransportBlockBits)==grant.TBSBits, ...
    'sixgr:truth:CompletedCSITXBindingMismatch','Do not transplant another grant, payload or matrix receipt.');
received=sixgr.util.structGet(state,'SharedDataRXCommittedIDs',strings(0,1));
assert(nnz(received==identity.TransmissionID)==1 && ...
    ~any(sixgr.util.structGet(state,'SharedDataNoDecodeCommittedIDs',strings(0,1))==identity.TransmissionID), ...
    'sixgr:truth:CompletedCSIRXCommitRequired','A started or uncommitted capture is not a completed decoded attempt.');

% Compare the complete admitted capsule, including supplied lifecycle and
% full PMI components, never just a local report ID or an equal scalar PMI.
assert(all(isfield(grant,{'CSIReportProvenance','CSIReportDecisionContext','CSIReportApplication'})), ...
    'sixgr:truth:CompletedCSIAdmissionRequired','The frozen grant must retain its admitted CSI capsule.');
capsule=grant.CSIReportProvenance; decision=grant.CSIReportDecisionContext;
reports=sixgr.util.structGet(state,'SharedGNBCSIReportTable',table());
assert(istable(reports) && all(ismember({'ReportIdentity','ObservationID'},reports.Properties.VariableNames)) && ...
    all(isfield(capsule,{'ReportIdentity','ObservationID','ReceiverObservationBound'})) && ...
    capsule.ReceiverObservationBound, ...
    'sixgr:truth:CompletedCSIAdmissionRequired','Require the original independently received CSI row.');
match=find(string(reports.ReportIdentity)==string(capsule.ReportIdentity) & ...
    string(reports.ObservationID)==string(capsule.ObservationID));
assert(isscalar(match),'sixgr:truth:CompletedCSIAdmissionRequired','One exact admitted report must remain retained.');
report=table2struct(reports(match,:));
checked=sixgr.truth.captureReceivedCSIProvenance(report,decision);
assert(isequaln(checked,capsule) && ...
    isequaln(mac.Grant.CSIReportProvenance,capsule) && ...
    isequaln(phy.LegacyGrantSnapshot.CSIReportProvenance,capsule) && ...
    capsule.UEIndex==identity.UEIndex && capsule.RNTI==identity.RNTI && ...
    capsule.ServingCell==grant.ServingCell && ...
    capsule.ReceiverClockDomain=="shared_receiver_sample_clock/v1" && ...
    capsule.ReceiverClockEpoch==owner.Physical.ConfigurationEpoch && ...
    capsule.ObservationSampleRateHz==owner.SampleRateHz, ...
    'sixgr:truth:CompletedCSIAdmissionMismatch','Retain the admitted report and original owner clock unchanged.');
frozen=sixgr.l2.mac.csiReportGrantApplication(grant,phy);
assert(isequaln(frozen,grant.CSIReportApplication) && ~frozen.WaveformApplicationVerified, ...
    'sixgr:truth:CompletedCSIFrozenApplicationMismatch','Frozen operands must not already claim waveform completion.');

% A supplied success flag is insufficient: require the original retained
% control record, receiver materialization digest and received grant binding.
controls=sixgr.util.structGet(state,'SharedReceivedGrantControls',{});
assert(isstruct(control) && isscalar(control) && ...
    all(isfield(control,{'Key','Grant','Allowed','ReceivedAssignment','AvailableAtSample'})) && ...
    isequal(control.Allowed,true) && nnz(cellfun(@(r)isequaln(r,control),controls))==1 && ...
    nnz(cellfun(@(r)string(r.Key)==string(control.Key),controls))==1, ...
    'sixgr:truth:CompletedCSIControlRequired','Use the unique receiver-owned accepted control record.');
sixgr.truth.bindReceivedPDCCHGrantEvidence(grant,control.Grant);
a=control.ReceivedAssignment;
assert(isstruct(a) && isscalar(a) && all(isfield(a, ...
    {'Source','AssignmentDigest','PayloadHash','ContextDigest','Direction','RNTI', ...
    'ControlAbsoluteSlot','DataAbsoluteSlot','NumLayers','MCS'})) && ...
    string(a.Source)=="received_dci_bits_plus_installed_connected_context" && ...
    string(a.AssignmentDigest)==localSHA(string(jsonencode(orderfields(rmfield(a,'AssignmentDigest'))))) && ...
    a.Direction=="DL" && a.RNTI==identity.RNTI && ...
    a.ControlAbsoluteSlot==grant.ControlAbsoluteSlot && a.DataAbsoluteSlot==grant.ScheduledAbsoluteSlot && ...
    a.NumLayers==phy.AntennaArchitecture.NumLayers && a.MCS==grant.MCSIndex && ...
    string(a.PayloadHash)==string(control.Grant.PDCCHGrantDCIId) && ...
    isequaln(control.Grant.CSIReportProvenance,capsule) && ...
    isequaln(control.Grant.PHYGrant.PrecodingState,phy.PrecodingState), ...
    'sixgr:truth:CompletedCSIControlMismatch','Received assignment, payload, frozen grant and CSI must agree.');

[post,~,tx,~,receiver]=sixgr.truth.sharedObservationEvidence(item.Planes,p);
planeIDs=string({item.Planes.ReceiverID});
txIndex=find(planeIDs=="gnb_"+grant.ServingCell+":tx");
rxIndex=find(planeIDs=="ue_"+item.UE+"_rx:post_rf");
assert(isscalar(txIndex) && isscalar(rxIndex) && ...
    isequal(item.Planes(txIndex).Observation,tx) && isequal(item.Planes(rxIndex).Observation,post) && ...
    tx.isComplete() && post.isComplete() && receiver.isComplete() && ...
    tx.StartSample==identity.StartSample && tx.EndSampleExclusive==identity.EndSampleExclusive && ...
    owner.Events.NextSampleIndex>=max(tx.EndSampleExclusive,post.EndSampleExclusive), ...
    'sixgr:truth:CompletedCSICaptureMismatch','Require the actual same-cell TX and same-UE complete RX buffers.');
componentReceipts=localEmission(owner,item,item.Planes(txIndex),receipt,p);
localReceiverSegments(owner,item.Planes(rxIndex));

assert(isstruct(res) && isscalar(res) && ...
    string(sixgr.util.structGet(res,'ExecutionStage',""))=="received_shared_stream_completed" && ...
    isfield(res,'TrialTable') && istable(res.TrialTable) && height(res.TrialTable)==1 && ...
    isfield(res,'ReceiveTiming') && isfield(res,'HARQ') && ...
    all(isfield(res.HARQ,{'SharedTransmissionID','ReceivedTimingEvidence','ReceivedAssignmentDigest'})) && ...
    string(res.HARQ.SharedTransmissionID)==identity.TransmissionID && ...
    string(res.HARQ.ReceivedAssignmentDigest)==string(a.AssignmentDigest), ...
    'sixgr:truth:CompletedCSIResultRequired','Require the original completed shared receiver result.');
t=res.TrialTable; names=string(t.Properties.VariableNames);
assert(all(ismember(["FrozenGrantContextId","ReceivedAssignmentDigest","ReceiverObservationSHA256", ...
        "CRCPass","CRCApplicable", ...
        "DLSCHDecodeAttempted","DecodeAttempted","Crash"],names)) && ...
    string(t.FrozenGrantContextId)==identity.PHYGrantContextId && ...
    string(t.ReceivedAssignmentDigest)==string(a.AssignmentDigest) && ...
    localText(t.ReceiverObservationSHA256) && ...
    isequal(double(t.Crash),0) && isequal(double(t.CRCApplicable),1) && ...
    isequal(double(t.DLSCHDecodeAttempted),1) && isequal(double(t.DecodeAttempted),1) && ...
    isscalar(t.CRCPass) && any(double(t.CRCPass)==[0 1]), ...
    'sixgr:truth:CompletedCSIReceiverOutcome','A crash or unavailable CRC is not a measured receiver outcome.');
for name=["UEIndex","RNTI","ServingCell"]
    if ismember(name,names)
        expected=capsule.(name);
        assert(isequal(double(t.(name)),expected),'sixgr:truth:CompletedCSIRowMismatch', ...
            'The receiver row belongs to another %s.',name);
    end
end
completed=res.HARQ.ReceivedTimingEvidence.ResultAvailableAtSample;
timing=sixgr.truth.receivedDataSymbolTiming(p,receiver,res.ReceiveTiming,completed);
assert(isequaln(timing,res.HARQ.ReceivedTimingEvidence) && completed<=owner.Events.NextSampleIndex && ...
    capsule.AvailableAtSample<=decision.AtSample && decision.AtSample<=control.AvailableAtSample && ...
    decision.AtSample<=receipt.FirstActiveSample && ...
    control.AvailableAtSample<=post.EndSampleExclusive && post.EndSampleExclusive<=completed, ...
    'sixgr:truth:CompletedCSIChronology','Use the retained result event, not a later callback clock.');
observed=sixgr.link.receivedWaveformEvidence(receiver);
for name=string(fieldnames(observed)).'
    if ismember(name,names)
        assert(isequaln(t.(name),observed.(name)),'sixgr:truth:CompletedCSIRowMismatch', ...
            'Retained receiver field %s does not match the actual decoder input.',name);
    end
end
matrices=localMatrices(p,receipt);

% Value-only output; no live owner, PHY object, channel tensor or private UE
% selection audit enters the evidence. Hashes seal exact retained tokens.
evidence=struct('Version',"completed_received_csi_application/v1", ...
    'Source',"received_CSI_owner_control_record_and_completed_shared_PDSCH", ...
    'Scope',"single_shared_attempt_native_resource_mapping_not_access_or_performance_qualification", ...
    'AdmittedCSI',capsule,'DecisionClock',decision,'FrozenApplication',frozen, ...
    'TransmissionIdentity',identity,'LogicalGrantContextID',logicalGrantID, ...
    'ReceiverWindowID',string(item.ID), ...
    'TransmitterID',extractBefore(planeIDs(txIndex),':tx'), ...
    'ReceiverID',extractBefore(planeIDs(rxIndex),':post_rf'), ...
    'ReceiverClockDomain',capsule.ReceiverClockDomain, ...
    'ReceiverClockEpoch',capsule.ReceiverClockEpoch, ...
    'CompletedAtSample',completed,'FirstActiveSample',receipt.FirstActiveSample, ...
    'TXCommittedAtSample',receipt.CommittedAtSample, ...
    'TXSampleSHA256',tx.sampleHash(),'PostRFSampleSHA256',post.sampleHash(), ...
    'ReceiverInput',observed,'ReceivedTiming',timing,'ExecutedComponentReceipts',componentReceipts, ...
    'AppliedMatrices',matrices,'WaveformApplicationVerified',true, ...
    'ReceiverOutcome',struct('CRCApplicable',true,'CRCPass',logical(t.CRCPass), ...
    'Source',"actual_completed_PDSCH_receiver_trial_not_application_acceptance_condition"), ...
    'AdditionalPHYExecutions',0,'FullScenarioQualified',false);
evidence.ReceivedControl=struct('Key',string(control.Key),'AvailableAtSample',control.AvailableAtSample, ...
    'Source',"retained_receiver_owned_control_record_and_binding_not_decoder_replay", ...
    'AssignmentJSON',string(jsonencode(a)),'AssignmentDigest',string(a.AssignmentDigest), ...
    'PayloadHash',string(a.PayloadHash),'ContextDigest',string(a.ContextDigest), ...
    'RawDecoderReplayRetained',false);
evidence.AdmittedCSIJSON=string(jsonencode(capsule));
evidence.AdmittedCSISHA256=localSHA(evidence.AdmittedCSIJSON);
evidence.ReceivedControl.AssignmentJSONSHA256=localSHA(evidence.ReceivedControl.AssignmentJSON);
evidence.ReceiverRowSampleHashBound=ismember("ReceiverObservationSHA256",names);
for name=["CurrentDecodeOKDomain","CurrentAttemptStandaloneCRCMeasured"]
    if isfield(res.HARQ,name), evidence.ReceiverOutcome.(name)=res.HARQ.(name); end
end
% Received report population and frozen preparation population are distinct
% coordinates. Never backfill either using the current state/filename.
evidence.ReceivedReportPopulation=localReportPopulation(capsule);
[evidence.PreparedPopulation,evidence.PreparedConfiguration,preparedCapsule,preparedToken,preparedSHA]= ...
    localPreparedPopulation(p,identity,owner.Physical.ConfigurationEpoch,receipt.FirstActiveSample);
evidence.PreparedSourcePopulation=preparedCapsule;
evidence.PreparedSourcePopulationJSON=preparedToken;
evidence.PreparedSourcePopulationSHA256=preparedSHA;
for name=["RunID","ExecutionID","ConfigHash","ScenarioID","RandomSeed","ChannelSeed"]
    left=evidence.ReceivedReportPopulation.(name); right=evidence.PreparedPopulation.(name);
    if localPresent(left) && localPresent(right)
        assert(isequaln(left,right),'sixgr:truth:CompletedCSIPopulationMismatch', ...
            'Received report and prepared transmission differ in %s.',name);
    end
end
evidence.PopulationScopeComplete=all(structfun(@localPresent,evidence.ReceivedReportPopulation)) && ...
    strlength(preparedToken)>0 && all(structfun(@localPresent,evidence.PreparedPopulation));
if strlength(preparedToken)>0
    evidence.PreparedSourcePointScope="retained_preparation_population_capsule_lifecycle_incomplete";
    if all(structfun(@localPresent,evidence.PreparedPopulation))
        evidence.PreparedSourcePointScope="retained_preparation_population_capsule_complete";
    end
elseif localPresent(evidence.PreparedPopulation.ConfiguredSNR_dB)
    evidence.PreparedSourcePointScope="configured_request_SNR_retained_source_sweep_population_unavailable";
else
    evidence.PreparedSourcePointScope="unavailable_no_retained_TX_source_point_capsule";
end
evidence.EvidenceJSON=string(jsonencode(sixgr.util.jsonSafeValue(evidence)));
evidence.EvidenceSHA256=localSHA(evidence.EvidenceJSON);
end

function receipts=localEmission(owner,item,plane,receipt,p)
% Original mapped-component digest and exact intervals are already retained
% by the owner. The composed TX capture may also contain other channels.
projection=receipt.WaveformToElementMatrix;
if string(p.RequestBinding.PHYGrant.AntennaArchitecture.WaveformDomain)=="element"
    mapped=p.Tx.Waveform;
    assert(isequal(projection,eye(size(projection),'like',projection)), ...
        'sixgr:truth:CompletedCSIMatrixMismatch','Element-domain IQ must retain the identity stream projection.');
else
    mapped=p.Tx.Waveform*projection.';
end
sha=string(sixgr.phy.waveform.WaveformHash.numeric(mapped));
cursor=p.StartSample; receipts=struct('StartSample',{},'EndSampleExclusive',{}, ...
    'ComponentID',{},'OriginalSampleSHA256',{},'NonzeroSampleCount',{});
for k=1:numel(plane.Segments)
    s=plane.Segments{k}; e=localExecuted(owner,s);
    roster=e.ExecutedContributors;
    r=find(string({roster.TransmitterID})==extractBefore(string(plane.ReceiverID),':tx'));
    assert(isscalar(r),'sixgr:truth:CompletedCSIEmissionRequired','The original transmitter must own every interval.');
    entry=roster(r); consumed=entry.Receipt;
    assert(consumed.Schema=="consumed_waveform_components/v1" && consumed.CompleteContributorList && ...
        consumed.StartSample==s.StartSample && consumed.EndSampleExclusive==s.EndSampleExclusive && ...
        consumed.SampleRateHz==p.SampleRateHz && entry.CommittedThroughSample>=s.EndSampleExclusive, ...
        'sixgr:truth:CompletedCSIEmissionRequired','Incomplete consumed-component receipt.');
    c=consumed.Components;
    hit=find(string({c.ComponentID})==string(item.ID));
    assert(isscalar(hit),'sixgr:truth:CompletedCSIEmissionRequired','The completed window must name the emitted component.');
    c=c(hit); stop=min(s.EndSampleExclusive,p.EndSampleExclusive);
    assert(c.StartSample==cursor && c.EndSampleExclusive==stop && stop>cursor && ...
        string(c.OriginalSampleSHA256)==sha && ...
        c.NonzeroSampleCount==nnz(mapped(cursor-p.StartSample+1:stop-p.StartSample,:)), ...
        'sixgr:truth:CompletedCSIEmissionRequired','Retain exact full emission, not merely a started TX receipt.');
    receipts(end+1)=struct('StartSample',c.StartSample,'EndSampleExclusive',c.EndSampleExclusive, ...
        'ComponentID',string(c.ComponentID),'OriginalSampleSHA256',string(c.OriginalSampleSHA256), ...
        'NonzeroSampleCount',c.NonzeroSampleCount); %#ok<AGROW>
    cursor=stop;
end
assert(cursor==p.EndSampleExclusive && sum([receipts.NonzeroSampleCount])>0, ...
    'sixgr:truth:CompletedCSIEmissionRequired','All actual component samples must have executed.');
end

function localReceiverSegments(owner,plane)
cursor=plane.Observation.StartSample;
for k=1:numel(plane.Segments)
    s=plane.Segments{k}; e=localExecuted(owner,s);
    assert(s.StartSample<=cursor && s.EndSampleExclusive>cursor && ...
        nnz(string({e.RX.ID})==extractBefore(string(plane.ReceiverID),':post_rf'))==1, ...
        'sixgr:truth:CompletedCSICaptureMismatch','Require contiguous actual receiver execution.');
    cursor=min(s.EndSampleExclusive,plane.Observation.EndSampleExclusive);
end
assert(cursor==plane.Observation.EndSampleExclusive, ...
    'sixgr:truth:CompletedCSICaptureMismatch','Receiver execution must reach the complete observation end.');
end

function e=localExecuted(owner,segment)
e=segment.Execution;
trace=owner.Events.ExecutionTrace;
hit=find(cellfun(@(s)s.StartSample==segment.StartSample && ...
    s.EndSampleExclusive==segment.EndSampleExclusive,trace));
assert(isscalar(hit) && all(isfield(e,{'ExecutedContributors','ConfigurationEpoch','SampleRateHz','RX','Source','ApproximationMode'})) && ...
    string(e.Source)=="composed_tx_retained_rf_per_link_channel_sum_receiver_noise_rf" && ...
    string(e.ApproximationMode)=="none" && ...
    e.ConfigurationEpoch==owner.Physical.ConfigurationEpoch && e.SampleRateHz==owner.SampleRateHz && ...
    isequaln(e.ExecutedContributors,trace{hit}.Execution.ExecutedContributors) && ...
    isequaln(e.RX,trace{hit}.Execution.RX), ...
    'sixgr:truth:CompletedCSIExecutionMismatch','Capture receipts must match the original successful owner execution.');
end

function e=localMatrices(p,receipt)
e=sixgr.truth.collectCompletedCSIDataMapping(p.Tx,receipt.WaveformToElementMatrix, ...
    p.RequestBinding.PHYGrant.PrecodingState);
end

function p=localReportPopulation(c)
p=struct();
for f=["RunID","ExecutionID","ConfigHash","ScenarioID","RandomSeed","ChannelSeed", ...
        "SweepPointIndex","ConfiguredSNR_dB"]
    p.(f)=c.(f);
end
end

function [population,configuration,capsule,token,sha]=localPreparedPopulation(prepared,identity,epoch,firstActive)
cfg=prepared.InputConfig;
population=struct('RunID',string(sixgr.util.structGet(cfg,'run.runTag',"")), ...
    'ExecutionID',string(sixgr.util.structGet(cfg,'run.executionID',"")), ...
    'ConfigHash',string(sixgr.util.structGet(cfg,'meta.configHash',"")), ...
    'ScenarioID',string(sixgr.util.structGet(cfg,'run.scenarioID',"")), ...
    'RandomSeed',NaN,'ChannelSeed',NaN,'SweepPointIndex',NaN, ...
    'ConfiguredSNR_dB',double(sixgr.util.structGet(prepared.RequestBinding,'SNR_dB',NaN)));
% cfg.run.seed can be UE-derived. It is not the global run seed that was
% frozen on the received report, nor an executed receiver noise-stream seed.
configuration=struct('PreparedRandomSeed',double(sixgr.util.structGet(cfg,'run.seed',NaN)), ...
    'PreparedChannelSeed',double(sixgr.util.structGet(cfg,'channel.seed',NaN)), ...
    'StoredConfigHash',population.ConfigHash, ...
    'ConfigHashRole',"retained_root_scenario_label_not_digest_of_derived_UE_configuration", ...
    'SeedRole',"retained_prepared_configuration_seeds_not_global_or_executed_noise_stream_seeds", ...
    'ConfiguredRequestSNR_dB',population.ConfiguredSNR_dB, ...
    'ConfiguredSNRRole',"immutable_request_configured_operating_point_not_measured_SINR_or_N0");
runtime=sixgr.util.structGet(cfg,'lls6g.runtime',struct());
hasCapsule=isfield(runtime,'PreparedDataPopulation');
hasSHA=isfield(runtime,'PreparedDataPopulationSHA256');
assert(hasCapsule==hasSHA,'sixgr:truth:CompletedCSIPreparedPopulationHash', ...
    'The original preparation population and its digest must be retained together.');
capsule=struct(); token=""; sha="";
if ~hasCapsule, return; end
capsule=runtime.PreparedDataPopulation;
required={'Version','Source','RunID','ExecutionID','ConfigHash','ScenarioID', ...
    'SweepPointIndex','ConfiguredSNR_dB','SourceRandomSeed','SourceChannelSeed', ...
    'PreparedRandomSeed','PreparedChannelSeed','UEIndex','Direction','GrantContextID', ...
    'CapturedAtSample','ReceiverClockDomain','ReceiverClockEpoch'};
assert(isstruct(capsule) && isscalar(capsule) && all(isfield(capsule,required)) && ...
    string(capsule.Version)=="prepared_data_population/v1" && ...
    string(capsule.Source)=="shared_coordinator_before_data_preparation", ...
    'sixgr:truth:CompletedCSIPreparedPopulationContract','Require the original pre-preparation population capsule.');
token=string(jsonencode(sixgr.util.jsonSafeValue(capsule)));
sha=string(runtime.PreparedDataPopulationSHA256);
assert(localText(sha) && sha==localSHA(token), ...
    'sixgr:truth:CompletedCSIPreparedPopulationHash','Do not alter or reconstruct the prepared population token.');
for name=["RunID","ExecutionID","ConfigHash","ScenarioID"]
    value=capsule.(name);
    assert((isstring(value)||ischar(value)) && isscalar(string(value)) && ...
        ~ismissing(string(value)) && isequal(string(value),population.(name)), ...
        'sixgr:truth:CompletedCSIPreparedPopulationMismatch', ...
        'The pre-preparation %s must equal its retained input configuration label.',name);
end
for name=["SourceRandomSeed","SourceChannelSeed","PreparedRandomSeed","PreparedChannelSeed","SweepPointIndex"]
    value=capsule.(name);
    assert(isnumeric(value) && isreal(value) && isscalar(value) && ...
        (isnan(value)||(isfinite(value)&&value>=0&&value==fix(value))), ...
        'sixgr:truth:CompletedCSIPreparedPopulationContract','Population seed/point coordinates must be explicit or missing.');
end
assert(isequaln(double(capsule.PreparedRandomSeed),configuration.PreparedRandomSeed) && ...
    isequaln(double(capsule.PreparedChannelSeed),configuration.PreparedChannelSeed) && ...
    isequaln(double(capsule.ConfiguredSNR_dB),population.ConfiguredSNR_dB) && ...
    localPresent(capsule.ConfiguredSNR_dB) && ...
    isequal(double(capsule.UEIndex),identity.UEIndex) && string(capsule.Direction)==prepared.Direction && ...
    string(capsule.GrantContextID)==identity.PHYGrantContextId && ...
    string(capsule.ReceiverClockDomain)=="shared_receiver_sample_clock/v1" && ...
    isequal(double(capsule.ReceiverClockEpoch),double(epoch)) && ...
    localPresent(capsule.CapturedAtSample) && capsule.CapturedAtSample>=0 && ...
    capsule.CapturedAtSample==fix(capsule.CapturedAtSample) && capsule.CapturedAtSample<=firstActive, ...
    'sixgr:truth:CompletedCSIPreparedPopulationMismatch', ...
    'Retain the original prepared UE seeds, request SNR, grant, direction and preparation clock.');
if isfield(capsule,'LogicalGrantContextID')
    logicalID=string(capsule.LogicalGrantContextID);
    assert(isscalar(logicalID) && ~ismissing(logicalID) && ...
        (strlength(logicalID)==0 || logicalID==string(sixgr.util.structGet( ...
        prepared.RequestBinding.Grant,'GrantContextId',""))), ...
        'sixgr:truth:CompletedCSIPreparedPopulationMismatch', ...
        'The original logical grant ID must match its own domain, not the frozen PHY digest.');
end
population.RandomSeed=double(capsule.SourceRandomSeed);
population.ChannelSeed=double(capsule.SourceChannelSeed);
population.SweepPointIndex=double(capsule.SweepPointIndex);
end

function tf=localText(x)
tf=(isstring(x)||ischar(x)) && isscalar(string(x)) && ~ismissing(string(x)) && strlength(string(x))>0;
end

function tf=localPresent(x)
if isstring(x) || ischar(x), tf=localText(x);
else, tf=isnumeric(x) && isscalar(x) && isfinite(x); end
end

function sha=localSHA(token)
