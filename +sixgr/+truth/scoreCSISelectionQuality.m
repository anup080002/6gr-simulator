function [summary,candidates]=scoreCSISelectionQuality(reference,selection,request,disturbance,policy)
%SCORECSISELECTIONQUALITY Private post-reception fixed-CRI selection study.
% This function never selects an on-air report or updates a receiver. H must
% contain simultaneous complete Nrx-by-Nport matrices on the explicit support
% reconstructed from the SAME executed propagation after practical selection.
% Per-port pilot CSV rows are not a complete channel snapshot population.
%
% Codebook matrices retain unit logical-port Frobenius power. Every candidate
% (including the actual selected tuple) is separately scaled to equal RAW GRID
% physical-chain coefficient power through the ACTUAL port-to-physical matrix.
% This is not unit time-average transmitted power or TRP. It is a hypothetical
% nominal-linear/noise-only engineering objective, NOT actual PDSCH throughput,
% CQI/BLER qualification, CRI optimality, or a TS-required selection algorithm.
% H and PortToPhysicalMatrix MUST include the same TX amplitude factor: if
% the retained H=G*B_mapper*a, supply B=a*B_mapper (with its matching digest),
% or remove a from H and supply raw B_mapper. Scaled H with unscaled B gives
% the wrong physical-power target. Common nonzero complex scaling of H and B
% leaves this fixed-power objective invariant with the same noise covariance.
%
% Reference/selection/noise identities must match exactly, including optional
% population fields. The caller owns evidence retrieval; caller-supplied flags
% do not replace retained shared-runtime receipts. Unsupported inputs throw:
% the caller may publish unavailable status, never substitute another operand.
arguments
    reference (1,1) struct
    selection (1,1) struct
    request (1,1) struct
    disturbance (1,1) struct
    policy (1,1) struct
end
localPolicy(policy);
localIdentity(reference.Identity);
assert(isequaln(reference.Identity,selection.Identity) && ...
    isequaln(reference.Identity,disturbance.Identity), ...
    'sixgr:truth:CSISelectionIdentity','Reference, frozen selection and executed noise identities differ.');
assert(string(reference.Source)=="same_execution_nominal_linear_CSI_RS_reference" && ...
    ~reference.ReceiverEstimatorInput && ~reference.RFImpairmentsIncluded && ...
    reference.AdditionalChannelExecutions==0 && reference.AdditionalRFExecutions==0, ...
    'sixgr:truth:CSISelectionReference','Only post-reception same-execution nominal references are accepted.');
plane="nominal_linear_CSI_RS_port_channel_on_actual_RX_FFT_clock";
assert(string(reference.ReferencePlane)==plane && string(disturbance.ReferencePlane)==plane, ...
    'sixgr:truth:CSISelectionPlane','Channel and noise must occupy the same declared amplitude/FFT plane.');
H=double(reference.H); B=double(reference.PortToPhysicalMatrix);
assert(isnumeric(reference.H) && ndims(H)<=3 && ~isempty(H) && all(isfinite(H(:))) && ...
    isnumeric(reference.PortToPhysicalMatrix) && ismatrix(B) && ~isempty(B) && ...
    all(isfinite(B(:))) && size(B,2)==size(H,2) && ...
    string(reference.PortToPhysicalMatrixSHA256)==sixgr.phy.mimo.MatrixContract.digest(B), ...
    'sixgr:truth:CSISelectionSpatialBasis','Retain complete finite channel snapshots and the exact executed port basis.');
support=double(reference.Support);
assert(isnumeric(reference.Support) && isreal(support) && ...
    isequal(size(support),[size(H,3),2]) && all(isfinite(support(:))) && ...
    all(support(:)>=0 & support(:)==fix(support(:))) && ...
    size(unique(support,'rows'),1)==size(support,1), ...
    'sixgr:truth:CSISelectionSupport','Each simultaneous channel matrix needs a unique [subcarrier0,symbol0] location.');
requestDigest=sixgr.util.sha256Hex(jsonencode(orderfields(request)));
assert(string(reference.Identity.RequestSHA256)==requestDigest && ...
    request.Epoch==reference.Identity.ConfigurationEpoch && ...
    string(request.ReportConfigID)==string(reference.Identity.ReportConfigID), ...
    'sixgr:truth:CSISelectionConfiguration','The pinned report request/epoch must match the reference identity.');
assert(strcmpi(string(request.CodebookType),'typei-singlepanel') && ...
    strcmpi(string(request.FrequencyGranularity),'wideband'), ...
    'sixgr:truth:CSISelectionUnsupportedCodebook','Only the enumerated wideband Type-I single-panel domain is qualified.');
ranks=double(request.RankDomain);
assert(isrow(ranks) && ~isempty(ranks) && all(isfinite(ranks)) && ...
    isequal(ranks,unique(ranks,'sorted')) && all(ranks==fix(ranks) & ranks>=1 & ...
    ranks<=min(size(H,1),size(H,2))) && request.Ports==size(H,2) && ...
    isequal(double(selection.RankDomain),ranks) && ismember(selection.RI,ranks), ...
    'sixgr:truth:CSISelectionRankDomain','Use the frozen legal receiver rank domain, not numerical rank or a clipped subset.');
assert(isfield(request,'AllowedRanks') && isequal(double(request.AllowedRanks),ranks), ...
    'sixgr:truth:CSISelectionRankDomain','AllowedRanks and the actual search RankDomain must agree explicitly.');
assert(selection.CRI==reference.Identity.ResourceOrdinal0 && ...
    string(selection.MeasurementID)==string(reference.Identity.MeasurementID) && ...
    string(selection.MeasurementResourceID)==string(reference.Identity.ResourceID) && ...
    selection.MeasurementSlot==reference.Identity.MeasurementSlot, ...
    'sixgr:truth:CSISelectionMeasurement','The frozen selection must refer to this resource/CRI and measurement.');
if request.Ports==2
    for field=["CodebookSubsetRestriction","I2Restriction"]
        assert(~isfield(request,field) || isempty(request.(field)), ...
            'sixgr:truth:CSISelectionUnsupportedRestriction', ...
            'Two-port restricted candidate enumeration is not implemented; never ignore the restriction.');
    end
end
R=localNoise(disturbance,size(H,1));
selectedInfo=sixgr.phy.mimo.MatrixContract.validate(selection.Precoder_W, ...
    double(request.Ports),double(selection.RI),ExpectedDigest=string(selection.PrecoderMatrixSHA256));
candidates=table(); selectedIndex=NaN;
for rankValue=ranks
    rankRequest=request; rankRequest.Rank=rankValue;
    domain=sixgr.phy.mimo.CodebookEngine.enumerate(rankRequest);
    for index=1:numel(domain.CandidateIndices)
        W=domain.Matrices(:,:,index);
        physical=B*W; physicalPower=sum(abs(physical(:)).^2);
        assert(isfinite(physicalPower) && physicalPower>0, ...
            'sixgr:truth:CSISelectionZeroPhysicalPower','A legal tuple has zero physical-chain excitation power in the retained port basis.');
        factor=sqrt(double(policy.PowerFactor)/physicalPower);
        [objective,perSupport,layerSINR]=localObjective(H,W*factor,R);
        components=struct();
        if isfield(domain,'PMIComponents'), components=domain.PMIComponents(index); end
        selected=rankValue==selection.RI && domain.CandidateIndices(index)==selection.PMI;
        if selected
            assert(string(domain.MatrixSHA256(index))==string(selectedInfo.MatrixSHA256), ...
                'sixgr:truth:CSISelectionMatrix','The frozen PMI must identify its exact normative matrix.');
            for field=string(fieldnames(components)).'
                assert(isfield(selection,field) && isequal(double(selection.(field)),double(components.(field))), ...
                    'sixgr:truth:CSISelectionPMITuple','Preserve every multi-component PMI field, not just a scalar/beam ordinal.');
            end
            selectedIndex=height(candidates)+1;
        end
        row=struct('Rank',rankValue,'PMI',double(domain.CandidateIndices(index)), ...
            'PMIComponentsJSON',string(jsonencode(components)), ...
            'MatrixSHA256',string(domain.MatrixSHA256(index)), ...
            'CodebookSpecification',string(domain.Specification), ...
            'LogicalFrobeniusPower',double(domain.FrobeniusPower(index)), ...
            'UnscaledPhysicalFrobeniusPower',physicalPower, ...
            'AppliedAmplitudeFactor',factor,'ScoredPhysicalFrobeniusPower',physicalPower*factor^2, ...
            'Objective_bpsHz',objective,'SelectedByReceiver',selected);
        row.SupportObjective_bpsHz={perSupport}; row.LayerSINR={layerSINR};
        candidates=[candidates;struct2table(row)]; %#ok<AGROW>
    end
end
assert(isfinite(selectedIndex),'sixgr:truth:CSISelectionNotInDomain', ...
    'Actual selection is absent from the complete supported legal candidate set.');
best=max(candidates.Objective_bpsHz);
sameRank=candidates.Rank==selection.RI;
rankBest=max(candidates.Objective_bpsHz(sameRank));
selectedScore=candidates.Objective_bpsHz(selectedIndex);
candidates.WithinJointTie=best-candidates.Objective_bpsHz<=policy.TieAbsoluteTolerance;
candidates.WithinReportedRankTie=sameRank & ...
    rankBest-candidates.Objective_bpsHz<=policy.TieAbsoluteTolerance;
power=candidates.UnscaledPhysicalFrobeniusPower;
domainRows=candidates(:,{'Rank','PMI','PMIComponentsJSON','MatrixSHA256','CodebookSpecification'});
domainDigest=sixgr.util.sha256Hex(jsonencode(table2struct(domainRows)));
summary=struct('ContractVersion',"sixgr_CSI_selection_quality/v1", ...
    'Identity',reference.Identity,'Request',request,'Policy',policy, ...
    'ReferenceSource',string(reference.Source),'ReferencePlane',plane, ...
    'Scope',"hypothetical_equal_raw_grid_chain_coefficient_power_nominal_linear_noise_only_fixed_CRI", ...
    'ObjectiveClassification',"IMPLEMENTATION_POLICY_NOT_NR_NORMATIVE_OPTIMALITY", ...
    'ScoringAvailable',true,'ReferenceUsedByReceiver',false, ...
    'ReferenceIncludesRFImpairments',false,'NoiseIndependentFromReceiverEstimate',true, ...
    'ActualPDSCHPerformanceQualified',false,'CQIBLERQualified',false,'CRISelectionQualified',false, ...
    'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0, ...
    'NoiseEvidence',disturbance,'ChannelSHA256',sixgr.phy.mimo.MatrixContract.digest(H), ...
    'Support',support,'SupportCount',size(support,1), ...
    'PortToPhysicalMatrixSHA256',string(reference.PortToPhysicalMatrixSHA256), ...
    'CandidateCount',height(candidates),'LegalRankDomain',ranks, ...
    'CandidateDomainSHA256',domainDigest, ...
    'UnscaledPhysicalCandidatePowerEqual',max(power)-min(power)<=policy.PhysicalPowerTolerance, ...
    'SelectedRank',double(selection.RI),'SelectedPMI',double(selection.PMI), ...
    'SelectedPMIComponentsJSON',candidates.PMIComponentsJSON(selectedIndex), ...
    'SelectedMatrixSHA256',string(selectedInfo.MatrixSHA256), ...
    'SelectedObjective_bpsHz',selectedScore,'BestReportedRankObjective_bpsHz',rankBest, ...
    'BestJointObjective_bpsHz',best, ...
    'ConditionalPMIRegret_bpsHz',rankBest-selectedScore, ...
    'RankRegret_bpsHz',best-rankBest,'JointRegret_bpsHz',best-selectedScore, ...
    'SelectedWithinJointTie',logical(candidates.WithinJointTie(selectedIndex)), ...
    'SelectedWithinReportedRankTie',logical(candidates.WithinReportedRankTie(selectedIndex)), ...
    'JointTieCount',nnz(candidates.WithinJointTie), ...
    'ReportedRankTieCount',nnz(candidates.WithinReportedRankTie));
end

function localPolicy(p)
assert(string(p.Objective)=="mean_support_sum_log2_one_plus_linear_mmse_sinr" && ...
    string(p.Receiver)=="linear_mmse" && ...
    string(p.PowerNormalization)=="unit_physical_chain_grid_coefficient_power", ...
    'sixgr:truth:CSISelectionPolicy','The objective, receiver and physical-power normalization must be explicit.');
validateattributes(p.PowerFactor,{'numeric'},{'scalar','real','finite','positive'});
assert(p.PowerFactor==1,'sixgr:truth:CSISelectionPolicy', ...
    'unit_physical_chain_grid_coefficient_power requires the explicitly supplied PowerFactor to equal one.');
validateattributes(p.TieAbsoluteTolerance,{'numeric'},{'scalar','real','finite','nonnegative'});
validateattributes(p.PhysicalPowerTolerance,{'numeric'},{'scalar','real','finite','nonnegative'});
end

function localIdentity(id)
assert(isstruct(id) && isscalar(id),'sixgr:truth:CSISelectionIdentity','One exact observation identity is required.');
for field=["ObservationID","ReceiverID","MeasurementID","MeasurementDigest", ...
        "ResourceID","ReceiverClockDomain","ReportConfigID","RequestSHA256"]
    assert(isfield(id,field),'sixgr:truth:CSISelectionIdentity','Missing identity field %s.',field);
    value=string(id.(field));
    assert(isscalar(value) && ~ismissing(value) && strlength(strtrim(value))>0, ...
        'sixgr:truth:CSISelectionIdentity','Identity field %s must be explicit.',field);
end
for field=["ConfigurationEpoch","ReceiverClockEpoch","ResourceOrdinal0", ...
        "MeasurementSlot","ObservationStartSample","ObservationEndSampleExclusive"]
    assert(isfield(id,field),'sixgr:truth:CSISelectionIdentity','Missing identity field %s.',field);
    validateattributes(id.(field),{'numeric'},{'scalar','real','finite','integer','nonnegative'});
end
validateattributes(id.SampleRateHz,{'numeric'},{'scalar','real','finite','positive'});
assert(id.ObservationEndSampleExclusive>id.ObservationStartSample, ...
    'sixgr:truth:CSISelectionIdentity','The completed RX interval must be nonempty.');
end

function R=localNoise(d,nRx)
assert(string(d.Source)=="executed_pre_rx_rf_noise_with_recorded_ofdm_gain", ...
    'sixgr:truth:CSISelectionNoise','Post-RF estimated covariance cannot replace independently executed nominal noise.');
validateattributes(d.SampleNoiseVariance,{'numeric'},{'scalar','real','finite','positive'});
validateattributes(d.SampleToGridNoiseVarianceGain,{'numeric'},{'scalar','real','finite','positive'});
validateattributes(d.NoiseStreamSeed,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
R=double(d.Covariance);
gridVariance=double(d.SampleNoiseVariance)*double(d.SampleToGridNoiseVarianceGain);
assert(isfinite(gridVariance) && gridVariance>0, ...
    'sixgr:truth:CSISelectionNoise','Executed sample-to-grid variance must remain finite and positive.');
expected=gridVariance*eye(nRx);
assert(isnumeric(d.Covariance) && isequal(size(R),[nRx nRx]) && ...
    all(isfinite(R(:))) && norm(R-expected,'fro')<=1e-12*norm(expected,'fro'), ...
    'sixgr:truth:CSISelectionNoise','Covariance must close from actual injected variance and recorded native OFDM gain.');
end

function [objective,perSupport,layerSINR]=localObjective(H,W,R)
% Independent arithmetic: form the receive filter and calculate desired,
% inter-layer and noise powers directly. Do NOT call the practical search or
% its error-covariance-to-SINR helper. Zero-channel layers have exact SINR 0.
nLayers=size(W,2); nSupport=size(H,3);
layerSINR=zeros(nSupport,nLayers);
for resource=1:nSupport
    A=H(:,:,resource)*W;
    F=(A*A'+R)\A;
    G=F'*A;
    for layer=1:nLayers
        desired=abs(G(layer,layer))^2;
        others=[1:layer-1 layer+1:nLayers];
        interference=sum(abs(G(layer,others)).^2);
        noise=real(F(:,layer)'*R*F(:,layer));
        if desired==0 && interference==0 && noise==0
            layerSINR(resource,layer)=0;
        else
            assert(isfinite(noise) && noise>0, ...
                'sixgr:truth:CSISelectionArithmetic','The independent receive-filter noise power must be positive.');
            layerSINR(resource,layer)=desired/(interference+noise);
        end
    end
end
assert(all(isfinite(layerSINR(:))) && all(layerSINR(:)>=0), ...
    'sixgr:truth:CSISelectionArithmetic','Independent layer SINRs must be finite and nonnegative.');
perSupport=sum(log2(1+layerSINR),2); objective=mean(perSupport);
end
