function out=projectAcceptedSRSDecisionEvidence(owner)
% Descriptive publication only. Never approve/refresh an SRS decision here.
% Raw latest sounding, accepted spatial computation, and scheduled SRI are
% distinct facts. A retained decision is not proof of PUSCH execution.
arguments
    owner (1,1) struct = struct()
end
out=struct('AcceptedSRSSpatialDecisionJSON',"",'AcceptedSRSSpatialDecisionSHA256',"", ...
    'AcceptedSRSDecisionContextJSON',"",'AcceptedSRSDecisionContextSHA256',"", ...
    'SRSCurrentInstallationJSON',"",'SRSCurrentInstallationSHA256',"", ...
    'AcceptedSRSProjectionStatus',"missing_accepted_decision_history", ...
    'AcceptedSRSEvidenceRole',"accepted_spatial_computation_source_not_latest_sounding_SRI_or_execution_proof", ...
    'AcceptedSRSMeasurementID',"",'AcceptedSRSResourceID',"", ...
    'AcceptedSRSConfigurationContextID',"",'AcceptedSRSNumPorts',NaN, ...
    'AcceptedSRSMeasurementSource',"",'AcceptedSRSMeasurementClockDomain',"", ...
    'AcceptedSRSProducerSlot',NaN,'AcceptedSRSAvailableSlot',NaN, ...
    'AcceptedSRSUEIndex',NaN,'AcceptedSRSRNTI',NaN,'AcceptedSRSServingCell',NaN, ...
    'AcceptedSRSRI',NaN,'AcceptedSRSTPMI',NaN, ...
    'AcceptedSRSMeasurementClockEpoch',NaN,'AcceptedSRSObservationStartSample',NaN, ...
    'AcceptedSRSObservationEndSampleExclusive',NaN,'AcceptedSRSObservationSampleRateHz',NaN, ...
    'AcceptedSRSResultCompletedAtSample',NaN,'AcceptedSRSResultAvailableAtSample',NaN, ...
    'AcceptedSRSCausalUsable',NaN,'AcceptedSRSCausalAgeSlots',NaN,'AcceptedSRSCausalStatus',"", ...
    'RawSRSMeasurementID',"",'RawSRSLastSuccessfulSlot',NaN,'RawSRSValid',NaN, ...
    'RawSRSCausalUsable',NaN,'RawSRSCausalAgeSlots',NaN,'RawSRSCausalStatus',"", ...
    'ScheduledSRI',NaN,'ScheduledSRSResourceIndicator',NaN);
for pair=["RawSRSMeasurementID","SRSCausalMeasurementId"; ...
        "RawSRSCausalStatus","SRSCausalStatus";"AcceptedSRSCausalStatus","AcceptedSRSCausalStatus"].'
    if isfield(owner,pair(2)), out.(pair(1))=textScalar(owner.(pair(2)),pair(2)); end
end
for pair=["RawSRSLastSuccessfulSlot","LastSuccessfulSRSSlot";"RawSRSValid","SRSValid"; ...
        "RawSRSCausalUsable","SRSCausalUsable";"RawSRSCausalAgeSlots","SRSCausalAgeSlots"; ...
        "AcceptedSRSCausalUsable","AcceptedSRSCausalUsable"; ...
        "AcceptedSRSCausalAgeSlots","AcceptedSRSCausalAgeSlots"; ...
        "ScheduledSRI","SRI";"ScheduledSRSResourceIndicator","SRSResourceIndicator"].'
    if isfield(owner,pair(2)), out.(pair(1))=numericScalar(owner.(pair(2)),pair(2)); end
end
% A single configured resource has zero SRI payload bits. Its scheduled
% index still belongs to the original packed control context, not to the
% accepted sounding measurement's resource ID or today's configuration.
scheduled=originalScheduledSRI(owner);
if isfinite(scheduled)
    for name=["ScheduledSRI","ScheduledSRSResourceIndicator"]
        assert(~isfinite(out.(name))||out.(name)==scheduled, ...
            'sixgr:truth:ScheduledSRIPublicationMismatch', ...
            'Scheduled SRI alias conflicts with the original packed UL control.');
        out.(name)=scheduled;
    end
end
% Current installation is a separate owner snapshot, not the older accepted
% measurement's configuration. Never reconstruct it from cfg or decision A.
installation=sixgr.util.structGet(owner,'SRSCurrentInstallation',struct());
frozenInstallation=sixgr.util.structGet(owner, ...
    'PHYGrant.LegacyGrantSnapshot.SRSCurrentInstallation',struct());
assert(isstruct(installation)&&isscalar(installation)&& ...
    isstruct(frozenInstallation)&&isscalar(frozenInstallation), ...
    'sixgr:truth:AcceptedSRSPublicationType','Retain the original scalar current-installation capsule.');
if isempty(fieldnames(installation)), installation=frozenInstallation;
elseif ~isempty(fieldnames(frozenInstallation))
    assert(isequaln(installation,frozenInstallation), ...
        'sixgr:truth:AcceptedSRSPublicationMismatch', ...
        'Supplied and frozen original SRS current installations differ.');
end
if ~isempty(fieldnames(installation))
    assert(all(isfield(installation,{'Version','Source','UEIndex','RNTI','ServingCell', ...
        'NCellID','ConfigurationEpoch','ConfigurationContextID','ReceiverNumElements', ...
        'ReceiverPortToElementMatrix'})) && ...
        string(installation.Version)=="current_srs_installation/v1" && ...
        string(installation.Source)=="current_runtime_endpoint_installation", ...
        'sixgr:truth:AcceptedSRSPublicationType','Unknown retained current-installation contract.');
    % Established wire representation: complex bases retain real/imaginary
    % arrays and dimensions. No basis or compatibility decision is recomputed.
    out.SRSCurrentInstallationJSON=string(jsonencode(sixgr.util.jsonSafeValue(installation)));
    out.SRSCurrentInstallationSHA256=sixgr.util.sha256Hex(out.SRSCurrentInstallationJSON);
end
decision=sixgr.util.structGet(owner,'AcceptedSRSSpatialDecision',struct());
frozen=sixgr.util.structGet(owner,'PHYGrant.PrecodingState.AcceptedSRSSpatialDecision',struct());
assert(isstruct(decision)&&isscalar(decision)&&isstruct(frozen)&&isscalar(frozen), ...
    'sixgr:truth:AcceptedSRSPublicationType','Retain the scalar accepted-source capsule.');
if isempty(fieldnames(decision)), decision=frozen;
elseif ~isempty(fieldnames(frozen))
    assert(isequaln(decision,frozen),'sixgr:truth:AcceptedSRSPublicationMismatch', ...
        'Grant and frozen PHY accepted SRS sources differ.');
end
context=sixgr.util.structGet(owner,'AcceptedSRSDecisionContext', ...
    sixgr.util.structGet(owner,'PHYGrant.PrecodingState.AcceptedSRSDecisionContext',struct()));
if isstruct(context)&&isscalar(context)&&~isempty(fieldnames(context))
    out.AcceptedSRSDecisionContextJSON=string(jsonencode(context));
    out.AcceptedSRSDecisionContextSHA256=sixgr.util.sha256Hex(out.AcceptedSRSDecisionContextJSON);
end
if isempty(fieldnames(decision)), return; end
required={'Version','Source','MeasurementId','SignalType','TargetType','TargetId', ...
    'ServingCell','RNTI','ProducerSlot','AvailableSlot','Valid','RI','PMI'};
assert(all(isfield(decision,required)) && ...
    string(decision.Version)=="accepted_srs_spatial_decision/v1" && ...
    string(decision.SignalType)=="SRS" && string(decision.TargetType)=="UE", ...
    'sixgr:truth:AcceptedSRSPublicationType','Unknown accepted-source contract.');
out.AcceptedSRSSpatialDecisionJSON=string(jsonencode(decision));
out.AcceptedSRSSpatialDecisionSHA256=sixgr.util.sha256Hex(out.AcceptedSRSSpatialDecisionJSON);
out.AcceptedSRSProjectionStatus="retained_owner_decision_not_reapproved_by_exporter";
for pair=["MeasurementID","MeasurementId";"ResourceID","ResourceId"; ...
        "ConfigurationContextID","SRSConfigurationContextID"; ...
        "MeasurementSource","MeasurementSource";"MeasurementClockDomain","MeasurementClockDomain"].'
    if isfield(decision,pair(2)), out.("AcceptedSRS"+pair(1))=textScalar(decision.(pair(2)),pair(2)); end
end
for pair=["ProducerSlot","ProducerSlot";"AvailableSlot","AvailableSlot"; ...
        "UEIndex","TargetId";"RNTI","RNTI";"ServingCell","ServingCell"; ...
        "RI","RI";"TPMI","PMI";"MeasurementClockEpoch","MeasurementClockEpoch"; ...
        "NumPorts","SRSNumPorts"; ...
        "ObservationStartSample","ObservationStartSample"; ...
        "ObservationEndSampleExclusive","ObservationEndSampleExclusive"; ...
        "ObservationSampleRateHz","ObservationSampleRateHz"; ...
        "ResultCompletedAtSample","ResultCompletedAtSample"; ...
        "ResultAvailableAtSample","ResultAvailableAtSample"].'
    if isfield(decision,pair(2)), out.("AcceptedSRS"+pair(1))=numericScalar(decision.(pair(2)),pair(2)); end
end
end

function value=numericScalar(value,name)
assert((isnumeric(value)||islogical(value))&&isreal(value)&&isscalar(value), ...
    'sixgr:truth:AcceptedSRSPublicationType','Expected supplied scalar %s.',name);
value=double(value); % Missing history remains NaN; explicit false remains 0.
end

function value=textScalar(value,name)
value=string(value);
assert(isscalar(value)&&~ismissing(value),'sixgr:truth:AcceptedSRSPublicationType', ...
    'Expected supplied scalar text %s.',name);
end

function value=originalScheduledSRI(owner)
value=NaN;
dci=sixgr.util.structGet(owner,'DCI',struct());
if ~isstruct(dci)||~isscalar(dci)|| ...
        strlength(string(sixgr.util.structGet(dci,'Format',"")))==0|| ...
        ~isequal(sixgr.util.structGet(dci,'BitExactPDCCHPayload',false),true)
    return;
end
if sixgr.phy.pdcch.normalizeDCIFormat(dci.Format)~="0_1", return; end
assert(all(isfield(dci,{'Bits','ContextData','ContextDigest','PayloadHash','DCIGrantContract'}))&& ...
    string(dci.DCIGrantContract)=="packed_from_finalized_scheduler_phy_grant", ...
    'sixgr:truth:ScheduledSRIPublicationAuthority','Require original finalized scheduler control authority.');
context=sixgr.phy.pdcch.DCIContext(dci.ContextData);
assert(string(context.Digest)==string(dci.ContextDigest)&&context.Data.DCIFormat=="0_1", ...
    'sixgr:truth:ScheduledSRIPublicationMismatch','Original UL control context digest differs.');
parsed=sixgr.phy.pdcch.DCIParser.parse(dci.Bits,context);
assert(string(parsed.PayloadHash)==string(dci.PayloadHash)&&parsed.Direction=="UL", ...
    'sixgr:truth:ScheduledSRIPublicationMismatch','Original UL control payload hash differs.');
if isfield(owner,'Direction')
    assert(upper(string(owner.Direction))=="UL", ...
        'sixgr:truth:ScheduledSRIPublicationMismatch','UL control belongs to a different grant direction.');
end
if isfield(owner,'RNTI')
    assert(isequal(double(owner.RNTI),double(context.Data.RNTIValue)), ...
        'sixgr:truth:ScheduledSRIPublicationMismatch','UL control belongs to a different RNTI.');
end
if isfield(parsed.Fields,'srs_resource_index0based')
    value=double(parsed.Fields.srs_resource_index0based);
    assert(isscalar(value)&&isfinite(value)&&value>=0&&value==fix(value), ...
        'sixgr:truth:ScheduledSRIPublicationAuthority','Invalid original scheduled resource selector.');
end
end
