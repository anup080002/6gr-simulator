function [metrics,rows,evidence,selectionReference]=scoreSharedCSIRSChannel(prepared,rx,source,captures)
% Independent post-reception CSI-RS scoring, never an estimator/CRI input.
% The reference is the same executed nominal LINEAR propagation operator,
% including power, loss, resource precoder, RX delay/LO and applied CFO
% correction. Other RF distortion remains in Hest, not in this reference.
% CSI-RS CDM ports cannot be scored by dividing a composite waveform by
% one pilot. Reconstruct each port from retained physical channel gains.
assert(prepared.ExecutionStage=="csirs_waveform_prepared_not_received" && ...
    source.Source=="actual_executed_link_contribution" && ...
    ~source.ReceiverEstimatorInput && source.AdditionalChannelExecutions==0 && ...
    source.AdditionalRFExecutions==0 && source.ChannelReferenceCoverageComplete && ...
    iscell(captures) && ~isempty(captures), ...
    'sixgr:truth:MissingCSIRSChannelReference', ...
    'Use actual independently retained same-execution channel coefficients after CSI computation.');
metrics=struct('NMSE_dB',NaN,'NMSEScoringAvailable',false, ...
    'ChannelNMSEComparedComplexValues',0,'ChannelNMSEPilotResourceCount',0, ...
    'ChannelNMSEErrorEnergy',NaN,'ChannelNMSEReferenceEnergy',NaN, ...
    'ChannelNMSEReferenceUsedByReceiver',false,'ChannelNMSEGainOrPhaseFitted',false, ...
    'ChannelNMSEReferenceIncludesRFImpairments',false, ...
    'ChannelNMSEQualificationMode',"same_execution_nominal_linear_channel_no_gain_or_phase_fit", ...
    'ChannelNMSEScope',"all_available_received_CSI_RS_resources_and_all_pilot_ports_RX_branches", ...
    'ChannelNMSEReferencePlane',"nominal_linear_CSI_RS_port_channel_on_actual_RX_FFT_clock", ...
    'ChannelNMSESource',"executed_channel_coefficients_and_actual_resource_precoders_after_CSI_selection", ...
    'ChannelNMSEMeasuredResourceCount',0,'ChannelNMSEConfiguredResourceCount',0, ...
    'ChannelNMSEAllResourcesMeasured',false);
rows=table(); selectionReference=struct();
carrier=prepared.Carrier; ofdm=rx.ReceiverOFDMInfo; fs=prepared.SampleRateHz;
K=12*carrier.NSizeGrid; L=carrier.SymbolsPerSlot; nfft=double(ofdm.Nfft);
assert(fs==ofdm.SampleRate && fs==nfft*carrier.SubcarrierSpacing*1000, ...
    'sixgr:truth:CSIRSReferenceSampling','Scoring must use the actual native receiver FFT clock.');
[delay,hz]=localReceiverClock(source);
correction=0;
if rx.ReceiverTrackingCorrection.CFOCorrectionApplied
    correction=double(rx.ReceiverTrackingCorrection.CFOCorrectionApplied_Hz);
end
validateattributes(correction,{'double'},{'scalar','real','finite'});
offset=prepared.ReceiveStartSample+rx.ReceiveTiming.AppliedTimingCorrectionSamples- ...
    delay-prepared.TransmitStartSample;
amplitude=double(prepared.PowerContext.AmplitudeScale);
validateattributes(amplitude,{'double'},{'scalar','real','finite','positive'});
base=captures{1}.Reference;
objectOffset=double(sixgr.util.structGet(base,'ObjectTimeOffsetSamples',0));
next=base.StartSample;
for k=1:numel(captures)
    c=captures{k}; r=c.Reference;
    assert((r.Source~="same_executed_NR_channel_path_gains_and_filters" || ...
        isfield(r,'ObjectTimeOffsetSamples')) && ...
        double(sixgr.util.structGet(r,'ObjectTimeOffsetSamples',0))==objectOffset, ...
        'sixgr:truth:CSIRSReferenceClock','Preserve the executed native-object to physical-clock mapping.');
    assert(c.LinkID==source.LinkID && c.TX==source.TransmitterID && c.RX==source.ReceiverID && ...
        sixgr.channel.isAppliedChannelReference(r) && r.Source==base.Source && ...
        r.StartSample==next && r.EndSampleExclusive>r.StartSample && ...
        r.SampleRateHz==fs && r.StateKey==base.StateKey && ...
        isequal(r.PathFilters,base.PathFilters) && ...
        r.NumTransmitAntennas==base.NumTransmitAntennas && ...
        r.NumReceiveAntennas==base.NumReceiveAntennas && ...
        r.NormalizeChannelOutputs==base.NormalizeChannelOutputs && ...
        size(r.PathGains,1)==r.EndSampleExclusive-r.StartSample && ...
        ~r.ReceiverEstimatorInput && r.AdditionalChannelExecutions==0, ...
        'sixgr:truth:IncompleteCSIRSChannelReference', ...
        'No channel replay, different link, missing sample, or reference interpolation is allowed.');
    validateattributes(c.AppliedLargeScaleAmplitudeGain,{'numeric'}, ...
        {'scalar','real','finite','positive'});
    next=r.EndSampleExclusive;
end
R=base.NumReceiveAntennas; T=base.NumTransmitAntennas;
assert(T==prepared.NumPhysicalTransmitAntennas && R==size(rx.RxGrid,3), ...
    'sixgr:truth:CSIRSReferenceAntennaMismatch','Use the executed physical TX/RX dimensions.');
normalization=1;
% nrTDLChannel/nrCDLChannel return gains with their configured output
% normalization ALREADY applied. Dividing by sqrt(Nrx) again is wrong.
slotFirst=mod(double(carrier.NSlot),double(ofdm.SlotsPerSubframe))*L;
lengths=double(ofdm.SymbolLengths(slotFirst+(1:L)));
cp=lengths-nfft; starts=[0 cumsum(lengths(1:end-1))];
events=prepared.Tx.CSIRSRuntimeEvent.ResourceEvents;
resources=sixgr.util.structGet(rx.CSIRSInfo,'Resources',[]);
if isempty(resources)
    resources=struct('ResourceID',rx.CSIRSInfo.ResourceID, ...
        'Indices',rx.CSIRSIndices,'Symbols',rx.CSIRSSymbols);
end
metrics.ChannelNMSEConfiguredResourceCount=numel(resources);
evidence=struct('Source',metrics.ChannelNMSESource, ...
    'ReferencePlane',metrics.ChannelNMSEReferencePlane, ...
    'RFImpairmentsIncluded',false,'ReceiverEstimatorInput',false, ...
    'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0, ...
    'GainOrPhaseFitted',false,'RecordedRXTimingOffset_samples',delay, ...
    'ExecutedRXCFO_Hz',hz,'AppliedReceiverCFOCorrection_Hz',correction, ...
    'TimingOffsetRelativeTX_samples',offset,'TXAmplitudeScale',amplitude, ...
    'ChannelOutputNormalizationGain',normalization, ...
    'ChannelOutputNormalizationAlreadyInPathGains',true, ...
    'ChannelObjectTimeOffsetSamples',objectOffset, ...
    'ExcludedRFOperators',"TX_DAC_IQ_PA_phase_noise_CFO_timing_and_RX_phase_noise_IQ_element_RF_ADC", ...
    'ReferenceScope',"same_symbol_OFDM_diagonal_only_ICI_ISI_and_RF_errors_remain_in_receiver_estimate", ...
    'Resources',struct('ResourceID',{},'WaveformPrecoderMatrix',{},'WaveformPrecoderDigest',{}));
est=rx.CSIRSChannelEstimation;
for ordinal=1:numel(resources)
    resource=resources(ordinal);
    H=rx.CSIRSChannelEstimate;
    if isfield(est,'ResourceMeasurements')
        measurement=est.ResourceMeasurements(ordinal);
        assert(measurement.ResourceID==resource.ResourceID, ...
            'sixgr:truth:CSIRSReferenceResourceMismatch','Preserve received resource identity/order.');
        if ~measurement.Available, continue; end
        H=measurement.Hest;
    elseif ~est.Available
        continue;
    end
    event=events([events.ResourceID]==resource.ResourceID);
    assert(isscalar(event) && isfield(event,'WaveformPrecoderMatrix'), ...
        'sixgr:truth:MissingCSIRSExecutedPrecoder','Retain the matrix actually used by the TX mapper.');
    W=event.WaveformPrecoderMatrix; P=size(W,2);
    assert(size(W,1)==T && all(isfinite(W),'all') && ...
        string(sixgr.phy.mimo.MatrixContract.digest(W))==string(event.WaveformPrecoderDigest) && ...
        isequal([size(H,1) size(H,2) size(H,3) size(H,4)],[K L R P]), ...
        'sixgr:truth:CSIRSReferenceSpatialMap','No reconstructed/alternate beam or mismatched receiver port map.');
    indices=double(resource.Indices(:));
    [~,symbols,~]=ind2sub([K L P],indices);
    reference=complex(nan(K,L,R,P,'like',H));
    for symbol=unique(symbols).'
        % One bounded OFDM symbol at a time. Do not concatenate or copy
        % the entire 64-by-4 channel capture just to score pilot symbols.
        first=prepared.TransmitStartSample+starts(symbol);
        count=offset+floor(cp(symbol)*ofdm.CyclicPrefixFraction)+nfft;
        gains=localChannelWindow(captures,first,count,fs,delay,hz,correction,prepared.ReceiveStartSample);
        h=sixgr.truth.receivedFFTChannelDiagonal(gains,base.PathFilters, ...
            nfft,cp(symbol),K,offset,ofdm.CyclicPrefixFraction);
        h=reshape(reshape(h,[],T)*W,K,1,R,P)*amplitude*normalization;
        reference(:,symbol,:,:)=h;
    end
    if nargout>3
        assert(isfield(est,'SelectedResourceOrdinal'), ...
            'sixgr:truth:MissingCSISelectedReference','Retain the actual selected resource ordinal.');
        if ordinal==double(est.SelectedResourceOrdinal)
            % Complete simultaneous RX-by-port matrices at the actual pilot
            % coordinate union, not an assumed full reporting-band support.
            [subcarriers,pilotSymbols,~]=ind2sub([K L P],indices);
            support=unique([subcarriers-1,pilotSymbols-1],'rows');
            snapshots=complex(zeros(R,P,size(support,1),'like',reference));
            for q=1:size(support,1)
                snapshots(:,:,q)=reshape(reference(support(q,1)+1,support(q,2)+1,:,:),R,P);
            end
            evaluatedSymbols=unique(support(:,2))+1;
            fftFirst=prepared.ReceiveStartSample+rx.ReceiveTiming.AppliedTimingCorrectionSamples+ ...
                starts(evaluatedSymbols)+floor(cp(evaluatedSymbols)*ofdm.CyclicPrefixFraction);
            effectiveMap=amplitude*W;
            selectionReference=struct('Source',"same_execution_nominal_linear_CSI_RS_reference", ...
                'ReferencePlane',evidence.ReferencePlane,'ReceiverEstimatorInput',false, ...
                'RFImpairmentsIncluded',false,'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0, ...
                'H',snapshots,'Support',support,'SupportScope',"selected_resource_pilot_union", ...
                'RawPortToPhysicalMatrix',W,'RawPortToPhysicalMatrixSHA256',string(event.WaveformPrecoderDigest), ...
                'PortToPhysicalMatrix',effectiveMap, ...
                'PortToPhysicalMatrixSHA256',sixgr.phy.mimo.MatrixContract.digest(effectiveMap), ...
                'TXAmplitudeScale',amplitude,'ResourceID',double(resource.ResourceID), ...
                'ResourceOrdinal0',ordinal-1,'ReceiverID',string(source.ReceiverID), ...
                'TransmitterID',string(source.TransmitterID),'LinkID',string(source.LinkID), ...
                'FFTStartSample',fftFirst(:), ...
                'FFTEndSampleExclusive',fftFirst(:)+nfft,'FFTSymbolIndex0',evaluatedSymbols(:)-1, ...
                'ReferenceScope',evidence.ReferenceScope);
            selectionReference.SupportConvention="zero_based_carrier_grid_subcarrier_and_slot_symbol";
            selectionReference.Carrier=struct('NSizeGrid',double(carrier.NSizeGrid), ...
                'NStartGrid',double(carrier.NStartGrid),'NCellID',double(carrier.NCellID), ...
                'SubcarrierSpacing_kHz',double(carrier.SubcarrierSpacing), ...
                'CyclicPrefix',string(carrier.CyclicPrefix),'NSlot',double(carrier.NSlot), ...
                'NFrame',double(carrier.NFrame));
            selectionReference.FrequencyConfiguration=prepared.ReceiverConfig.frequency;
            selectionReference.ExecutedClockOperators=struct( ...
                'RecordedRXTimingOffset_samples',delay,'ExecutedRXCFO_Hz',hz, ...
                'AppliedReceiverCFOCorrection_Hz',correction, ...
                'TimingOffsetRelativeTX_samples',offset, ...
                'ChannelObjectTimeOffsetSamples',objectOffset, ...
                'ReferenceSource',evidence.Source,'ExcludedRFOperators',evidence.ExcludedRFOperators);
        end
    end
    context=struct('Channel',"CSI-RS",'Slot',prepared.RuntimeSlot, ...
        'UEIndex',double(sixgr.util.structGet(prepared.ReceiverConfig,'lls6g.userContext.RuntimeUEIndex',NaN)), ...
        'ConfiguredSNR_dB',prepared.RequestedSNR_dB, ...
        'ChannelEstimateSource',rx.CSIChannelEstimateSource, ...
        'ChannelReferenceSource',evidence.Source,'ChannelReferencePlane',evidence.ReferencePlane);
    [part,~]=sixgr.report.buildReceiverChannelEstimateTable(H,reference,indices,context);
    part.ResourceID=repmat(double(resource.ResourceID),height(part),1);
    part.ResourceOrdinal0=repmat(ordinal-1,height(part),1);
    part.SelectedForCSI=repmat(ordinal==double(sixgr.util.structGet(est,'SelectedResourceOrdinal',NaN)),height(part),1);
    part.WaveformPrecoderDigest=repmat(string(event.WaveformPrecoderDigest),height(part),1);
    part.ReferenceRFImpairmentsIncluded=false(height(part),1);
    part.RFComparisonScope=repmat(evidence.ReferenceScope,height(part),1);
    rows=[rows;part]; %#ok<AGROW>
    evidence.Resources(end+1)=struct('ResourceID',resource.ResourceID, ...
        'WaveformPrecoderMatrix',W,'WaveformPrecoderDigest',event.WaveformPrecoderDigest); %#ok<AGROW>
    metrics.ChannelNMSEMeasuredResourceCount=metrics.ChannelNMSEMeasuredResourceCount+1;
    metrics.ChannelNMSEPilotResourceCount=metrics.ChannelNMSEPilotResourceCount+numel(indices);
end
if isempty(rows), return; end
metrics.ChannelNMSEErrorEnergy=sum(rows.ChannelErrorEnergy);
metrics.ChannelNMSEReferenceEnergy=sum(rows.ReferenceChannelEnergy);
assert(metrics.ChannelNMSEReferenceEnergy>0,'sixgr:truth:ZeroCSIRSChannelReference', ...
    'A zero reference cannot qualify channel-estimation NMSE.');
metrics.NMSE_dB=10*log10(metrics.ChannelNMSEErrorEnergy/metrics.ChannelNMSEReferenceEnergy);
metrics.NMSEScoringAvailable=true;
metrics.ChannelNMSEComparedComplexValues=height(rows);
metrics.ChannelNMSEAllResourcesMeasured=metrics.ChannelNMSEMeasuredResourceCount==numel(resources);
end

function [delay,hz]=localReceiverClock(source)
segments=source.ReceiverClockExecution.ReceiveStreamExecutionSegments;
delay=NaN; hz=NaN;
for k=1:numel(segments)
    endpoints=segments{k}.Execution.RX;
    endpoint=endpoints(string({endpoints.ID})==source.ReceiverID);
    assert(isscalar(endpoint) && all(isfield(endpoint.Replay, ...
        {'InjectedTimingOffset_samples','CFOApplied','InjectedCFO_Hz','RFStageOrder'})), ...
        'sixgr:truth:MissingCSIRSReceiverClock','Use recorded RX-only operators, not configured or TX+RX values.');
    clock=endpoint.Replay;
    d=double(clock.InjectedTimingOffset_samples); f=0;
    if clock.CFOApplied, f=double(clock.InjectedCFO_Hz); end
    validateattributes(d,{'double'},{'scalar','real','finite','integer','nonnegative'});
    validateattributes(f,{'double'},{'scalar','real','finite'});
    order=split(string(clock.RFStageOrder),'>');
    assert(any(order=="rx_timing") && any(order=="rx_lo_cfo") && ...
        find(order=="rx_timing",1)<find(order=="rx_lo_cfo",1), ...
        'sixgr:truth:CSIRSReceiverOperatorOrder','Scoring must match the executed delay-before-LO order.');
    if k==1, delay=d; hz=f; end
    assert(d==delay && f==hz,'sixgr:truth:ChangingCSIRSReceiverClock', ...
        'Changing RF clocks need their full executed phase history, not one guessed scalar.');
end
assert(isfinite(delay) && isfinite(hz),'sixgr:truth:MissingCSIRSReceiverClock','No recorded RX clock.');
end

function gains=localChannelWindow(captures,first,count,fs,delay,hz,correction,rxFirst)
base=captures{1}.Reference;
validateattributes(count,{'double'},{'scalar','real','finite','integer','positive'});
gains=complex(zeros(count,size(base.PathGains,2),base.NumTransmitAntennas, ...
    base.NumReceiveAntennas,'like',base.PathGains));
next=first;
for k=1:numel(captures)
    c=captures{k}; r=c.Reference;
    a=max(first,r.StartSample); b=min(first+count,r.EndSampleExclusive);
    if b<=a, continue; end
    assert(a==next,'sixgr:truth:IncompleteCSIRSFFTReference','A scored FFT window has missing actual channel samples.');
    at=(a-r.StartSample+1):(b-r.StartSample);
    objectOffset=double(sixgr.util.structGet(r,'ObjectTimeOffsetSamples',0));
    validateattributes(objectOffset,{'double'},{'scalar','real','finite','integer','nonnegative'});
    assert(all(abs(double(r.SampleTimes_s(at))*fs-objectOffset-(a:b-1).')<1e-5), ...
        'sixgr:truth:CSIRSReferenceClock','Retained channel sample times must match the physical clock.');
    postClock=(a:b-1).'+delay;
    phase=exp(2i*pi/fs*(hz*postClock-correction*(postClock-rxFirst)));
    gains((a-first+1):(b-first),:,:,:)=r.PathGains(at,:,:,:).* ...
        reshape(phase*c.AppliedLargeScaleAmplitudeGain,[],1,1,1);
    next=b;
end
assert(next==first+count,'sixgr:truth:IncompleteCSIRSFFTReference', ...
    'Do not pad or extrapolate a missing channel-reference FFT sample.');
end
