function result=receiveCellMsg3(context,post)
% Caller validates exact original stream completion.
% This function performs one receiver decode, never another RF/channel run.
id='sixgr:truth:CellMsg3ReceiveAuthority';
p=context.Plan;
assert(p.ContractVersion=="cell_Msg3_receive_plan/v1" && ...
    p.SHA256==hash(rmfield(p,'SHA256')) && isa(post,'sixgr.phy.waveform.WaveformObservationBuffer') && ...
    post.isComplete() && post.StartSample==p.ReceiveStartSample && ...
    post.EndSampleExclusive==p.ReceiveEndSampleExclusive && post.SampleRateHz==p.SampleRateHz && ...
    post.NumReceiveAntennas==p.NumReceiveAntennas,id,'Use the original complete registered cell receive interval.');
a=sixgr.phy.ra.resolveMsg3PUSCHAllocation(context.Config,p.RAContext,p.Grant);
assert(a.AbsoluteSlot==p.AbsoluteSlot0 && a.TransportBlockSize==p.TransportBlockSize && ...
    isequaln(a.ResourceAccounting,p.ResourceAccounting) && a.PUSCH.RNTI==p.TemporaryCRNTI, ...
    id,'The decoder geometry must be the original actually emitted RAR grant.');
rx=sixgr.phy.ra.receiveMsg3PUSCHPhysical(post,context.Config,p.RAContext,p.Grant);
assert(islogical(rx.Ok)&&isscalar(rx.Ok),id,'The actual native receiver must publish an explicit CRC outcome.');
result=struct('ContractVersion',"cell_Msg3_receive_result/v1", ...
    'ServingCell',p.ServingCell,'TemporaryCRNTI',p.TemporaryCRNTI,'RAPID',p.RAPID, ...
    'PlanSHA256',p.SHA256,'RARPayloadSHA256',p.RARPayloadSHA256, ...
    'OriginalReceiveSHA256',post.sampleHash(),'ObservationStartSample',post.StartSample, ...
    'ObservationEndSampleExclusive',post.EndSampleExclusive,'SampleRateHz',post.SampleRateHz, ...
    'CRCPass',rx.Ok,'SemanticAccepted',false,'SemanticStatus',"not_attempted_failed_CRC", ...
    'SemanticErrorIdentifier',"",'SemanticErrorMessage',"",'ReceivedMACBytes',uint8.empty(1,0), ...
    'ReceivedMACSHA256',"",'Message',struct(),'SemanticInspection',struct(),'Receiver',rx, ...
    'Source',"original_cell_receiver_on_emitted_RAR_grant_no_UE_TX_or_RAR_decode_dependency", ...
    'MACRRCStandardsQualified',false);
if rx.Ok
    bits=rx.TransportBlock;
    assert(numel(bits)==a.TransportBlockSize && all(bits(:)==0|bits(:)==1),id, ...
        'Keep the actual complete CRC-checked transport block, never TX-private payload length.');
    bytes=uint8(reshape(double(bits),8,[]).'*(2.^(7:-1:0)).');
    result.ReceivedMACBytes=bytes(:).';
    result.ReceivedMACSHA256=sixgr.protocol.ProtocolHash.bytes(bytes);
    inspected=sixgr.mac.ra.inspectNRMsg3MACPDU(bytes);
    assert(result.ReceivedMACSHA256==inspected.OriginalMACSHA256,id, ...
        'Receiver and semantic inspection must preserve the same original uint8 MAC bytes.');
    result.SemanticInspection=inspected;
    result.Message=inspected.Message;
    result.SemanticAccepted=inspected.Accepted;result.SemanticStatus=inspected.Status;
    result.SemanticErrorIdentifier=inspected.ErrorIdentifier;
    result.SemanticErrorMessage=inspected.ErrorMessage;
end
end
function h=hash(v)
h=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(v))));
end
