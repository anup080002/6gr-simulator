function state=commitInitialNRMACReset(state,ue,attempt,plan,retirement)
% apply a validated initial-only transaction, preserving peer/history.
id='sixgr:truth:NRRRCInitialReset';
assert(attempt.Status=="t300_expired_pending_reset" && ...
    isequaln(plan.Context,attempt.Context) && plan.ExpirySample==attempt.ExpirySampleExclusive && ...
    retirement.UEIndex==ue && retirement.ResetSample==plan.ExpirySample && ...
    retirement.SampleRateHz==attempt.Context.SampleRateHz && ...
    retirement.ClockEpoch==attempt.Context.ConfigurationEpoch,id,'Original reset scope changed.');
assert(retirement.ContractVersion=="initial_NR_access_physical_retirement/v1" && ...
    retirement.SHA256==string(sixgr.util.sha256Hex(jsonencode(rmfield(retirement,'SHA256')))) && ...
    isequal(retirement.AttemptRunIDs,attempt.MACAttemptRunIDs) && ...
    ~retirement.EmittedSamplesChanged && ~retirement.GNBCellResponsesCancelled,id, ...
    'Retain the exact target-only physical retirement without changing emitted samples.');
receipt=struct('ContractVersion',"initial_NR_T300_MAC_reset/v1", ...
    'Context',plan.Context,'ResetSample',plan.ExpirySample,'RequestSHA256',plan.RequestSHA256, ...
    'PhysicalRetirement',retirement,'HARQResetReceipts',{{}}, ...
    'ExistingRLCBearerCount',0,'ExistingRLCReestablishmentRequired',false, ...
    'ApplicationBytesDropped',0,'ReceivedSystemInformationPreserved',true, ...
    'GNBCellResponsesCancelled',false,'ResetExecuted',true, ...
    'UpperLayerIndication',"initial_RRC_establishment_failure_T300");
for k=1:numel(plan.HARQOwners)
    context=struct('ResetSample',plan.ExpirySample,'SampleRateHz',plan.Context.SampleRateHz, ...
        'ClockEpoch',plan.Context.ConfigurationEpoch,'Reason',"initial_T300_expiry", ...
        'SourceEventID',retirement.OriginalTimerID);
    receipt.HARQResetReceipts{end+1,1}=plan.HARQOwners{k}.resetUE(plan.HARQRNTIs(k),context);
end
% Each removed owner remains in the archive; clearing an active timer/data
% slot does not erase its original observation or any completed history.
for name=["PendingRAAttempts","RARetryByUE","ConnectedULTimingByUE", ...
        "SharedUEULPowerControlStates"]
    if isfield(state,name)&&numel(state.(name))>=ue,state.(name){ue}=[];end
end
if isfield(state,'UEConfiguredSRProcedures') && size(state.UEConfiguredSRProcedures,1)>=ue
    state.UEConfiguredSRProcedures(ue,:)={[]};
end
state.AccessState(ue)="failed_T300";
state.TimeAlignmentState(ue)="expired_by_initial_MAC_reset";
for name=["LastTimingAdvanceSamplesByUE","LastTimingAdvanceUsByUE", ...
        "LastTimingAdvanceEffectiveAtSampleByUE"]
    if isfield(state,name)&&numel(state.(name))>=ue,state.(name)(ue)=NaN;end
end
if isfield(state,'LastTimingAdvanceSourceByUE'),state.LastTimingAdvanceSourceByUE(ue)="";end
if isfield(state,'TimingAdvanceUpdateRequiredByUE'),state.TimingAdvanceUpdateRequiredByUE(ue)=true;end
if isfield(state,'TimingAdvanceUpdateStatusByUE'),state.TimingAdvanceUpdateStatusByUE(ue)="initial_MAC_reset";end
receipt.SHA256=string(sixgr.util.sha256Hex(jsonencode(receipt)));
attempt=attempt.resetCompleted(receipt);
state.NRRRCSetupAttemptsByUE{ue}=attempt;
archive=struct('UEIndex',ue,'Attempt',attempt,'OriginalOwners',plan.Archive,'ResetReceipt',receipt);
if ~isfield(state,'RetiredInitialNRRAAttempts'),state.RetiredInitialNRRAAttempts={};end
state.RetiredInitialNRRAAttempts{end+1,1}=archive;
if ~isfield(state,'NRRRCUpperLayerIndications'),state.NRRRCUpperLayerIndications={};end
state.NRRRCUpperLayerIndications{end+1,1}=receipt;
% An explicit upper-layer restart API is separate; neither PRACH opportunity
% nor an old receiver callback may implicitly create a replacement attempt.
end
