function comparisons=scoreSharedPDSCHCSIRSComparison(snapshot,prepared,source,captures,owner,item,varargin)
% Bind two independently received estimates to this completed shared window.
% No CSI estimate is synthesized if the independent CSI component was absent.
comparisons=struct([]);
if ~isfield(snapshot,'PairedCSIRSEstimates'), return; end
capture=snapshot.PairedCSIRSEstimates;
if isempty(capture.Resources), return; end
assert(isa(owner,'sixgr.truth.CoupledWaveformStream') && ...
    isa(prepared,'sixgr.link.PreparedDataTransmission') && prepared.Direction=="DL" && ...
    string(item.Kind)=="PDSCH" && item.Context.Prepared.StartSample==prepared.StartSample && ...
    capture.Contract=="same_grid_PDSCH_CSI_RS_estimates/v1" && ...
    ~capture.ReferenceUsedByReceiver && capture.AdditionalReceiverExecutions==0, ...
    'sixgr:truth:PairedChannelOwner','Use actual retained receiver estimates and their completed owner.');
identity=sixgr.truth.preparedDataTransmissionIdentity(prepared,item.UE);
assert(isequaln(identity,item.Context.TransmissionIdentity), ...
    'sixgr:truth:PairedChannelTXIdentity','No replacement prepared data identity.');
records=owner.DataTransmissions;
data=records(arrayfun(@(x)x.Identity.TransmissionID==identity.TransmissionID,records));
assert(isscalar(data) && isequaln(data.Identity,identity) && ...
    isequaln(data.WaveformToElementMatrix,item.Context.WaveformToElementMatrix) && ...
    data.FirstActiveSample>=prepared.StartSample && data.FirstActiveSample<prepared.EndSampleExclusive && ...
    owner.Events.NextSampleIndex>=prepared.EndSampleExclusive, ...
    'sixgr:truth:PairedChannelTXIdentity','Require actual emitted data, retained map and completed sample clock.');
ids=string({item.Planes.ReceiverID});
post=item.Planes(endsWith(ids,':post_rf')).Observation;
tx=item.Planes(endsWith(ids,':tx')).Observation;
assert(post.isComplete() && tx.isComplete() && post.StartSample==prepared.ReceiveStartSample && ...
    post.EndSampleExclusive>=prepared.ReceiveEndSampleExclusive && tx.StartSample==prepared.StartSample && ...
    tx.EndSampleExclusive==prepared.EndSampleExclusive && post.SampleRateHz==prepared.SampleRateHz && ...
    extractBefore(ids(endsWith(ids,':post_rf')),':post_rf')==source.ReceiverID && ...
    extractBefore(ids(endsWith(ids,':tx')),':tx')==source.TransmitterID, ...
    'sixgr:truth:PairedChannelCaptureIdentity','Retain actual complete endpoint captures, not only a started TX receipt.');
assert(numel(varargin)==1,'sixgr:truth:PairedReceiverInputRequired', ...
    'Supply the original completed decoder-input buffer and its executed gain-compensation evidence.');
planeBinding=localReceiverPlaneBinding(varargin{1},post,item,source,identity,owner.Physical.ConfigurationEpoch);
planeBindingJSON=string(jsonencode(sixgr.util.jsonSafeValue(planeBinding)));
planeBindingSHA256=string(sixgr.phy.waveform.WaveformHash.bytes(planeBindingJSON));
assert(isequal(double(prepared.Tx.DMRSIndices(:)),capture.DMRSPilotIndices) && ...
    isequaln(prepared.Tx.DMRSSymbols(:),capture.DMRSPilotSymbols), ...
    'sixgr:truth:PairedChannelDMPilots','The actual RX pilot identities must match emitted DMRS; no assumed allocation.');
receiptFields={'ExecutedResourceMaps','TXAmplitudeScale','TransmitterID','TransmitStartSample', ...
    'TransmitObservationSHA256','CarrierIdentity','PopulationIdentity'};
receipts=owner.CSIRSTransmissions;
if ~isempty(receipts) && ~all(isfield(receipts,receiptFields)), return; end % historical missing operands stay missing
for k=1:numel(capture.Resources)
    r=capture.Resources(k);
    result=struct('ResourceID',r.ResourceID,'ResourceOrdinal0',r.ResourceOrdinal0, ...
        'Status',"unavailable_no_completed_same_slot_CSI_RS_transmission",'Score',struct(), ...
        'Rows',table(),'Operands',struct(),'Evidence',struct());
    if r.Status~="captured_same_grid_estimates_reference_not_bound"
        result.Status=r.Status; comparisons=localAppend(comparisons,result); continue;
    end
    hit=[];
    for n=1:numel(receipts)
        e=receipts(n);
        if e.TransmitterID~=source.TransmitterID || e.TransmitStartSample~=prepared.StartSample || ...
                e.SampleRateHz~=prepared.SampleRateHz || e.PhysicalConfigurationEpoch~=owner.Physical.ConfigurationEpoch
            continue;
        end
        maps=e.ExecutedResourceMaps;
        if any([maps.ResourceID]==r.ResourceID), hit(end+1)=n; end %#ok<AGROW>
    end
    if isempty(hit), comparisons=localAppend(comparisons,result); continue; end
    assert(isscalar(hit),'sixgr:truth:AmbiguousPairedCSITransmission', ...
        'Duplicate resource IDs on the same executed endpoint/slot need separate receiver resource identity.');
    e=receipts(hit); c=e.CarrierIdentity; carrier=capture.Carrier;
    assert(e.CommittedAtSample==e.EndSampleExclusive && e.EndSampleExclusive<=owner.Events.NextSampleIndex && ...
        e.ServingCell==prepared.RequestBinding.Grant.ServingCell && ...
        e.FirstActiveSample>=e.TransmitStartSample && e.FirstActiveSample<e.EndSampleExclusive && ...
        c.NSizeGrid==carrier.NSizeGrid && c.NStartGrid==carrier.NStartGrid && ...
        c.SubcarrierSpacing==carrier.SubcarrierSpacing && c.CyclicPrefix==string(carrier.CyclicPrefix) && ...
        c.NSlot==carrier.NSlot && c.NFrame==carrier.NFrame && strlength(e.TransmitObservationSHA256)==64, ...
        'sixgr:truth:PairedCSITransmissionScope','CSI resource receipt must be complete on the same native carrier and clock.');
    map=e.ExecutedResourceMaps([e.ExecutedResourceMaps.ResourceID]==r.ResourceID);
    assert(isscalar(map) && isequal(double(map.LogicalPilotIndices(:)),r.CSIRSPilotIndices) && ...
        isequaln(map.LogicalPilotSymbols(:),r.CSIRSPilotSymbols) && ...
        string(sixgr.phy.mimo.MatrixContract.digest(map.WaveformPrecoderMatrix))==string(map.WaveformPrecoderDigest), ...
        'sixgr:truth:PairedCSIPilotIdentity','Require the actual emitted CSI pilot/map, not configured resource labels.');
    amplitude=double(e.TXAmplitudeScale);
    validateattributes(amplitude,{'double'},{'scalar','finite','positive'});
    csiMap=amplitude*double(map.WaveformPrecoderMatrix);
    [dataMaps,mapEvidence]=localDataMaps(prepared,data.WaveformToElementMatrix,r.Support);
    [physical,reference]=sixgr.truth.sharedNominalPhysicalChannelOnSupport(capture,prepared,source,captures,r.Support);
    [score,rows,operands]=sixgr.report.scoreDMRSCSIRSCommonOperands( ...
        r.DMRSEstimate,r.CSIRSEstimate,physical,csiMap,dataMaps,r.Support);
    result.Status=score.Status; result.Score=score; result.Rows=rows; result.Operands=operands;
    % Keep executed receipt values, not live/configuration class objects that
    % are irrelevant to the arithmetic and can change serialization identity.
    emissionReceipt=rmfield(e,{'ReferenceConfiguration','ReportConfiguration','FrameIdentity'});
    result.Evidence=struct('Contract',"same_execution_paired_DMRS_CSI_RS/v2", ...
        'ReceiverWindowID',string(item.ID),'ReceiverID',source.ReceiverID, ...
        'TransmitterID',source.TransmitterID,'LinkID',source.LinkID, ...
        'ReceiverObservationSHA256',planeBinding.ReceiverInput.ReceiverObservationSHA256, ...
        'PostRFSampleSHA256',post.sampleHash(),'TransmitterObservationSHA256',tx.sampleHash(), ...
        'ReceiverPlaneBinding',planeBinding,'ReceiverPlaneBindingJSON',planeBindingJSON, ...
        'ReceiverPlaneBindingSHA256',planeBindingSHA256, ...
        'ObservationStartSample',post.StartSample,'ObservationEndSampleExclusive',post.EndSampleExclusive, ...
        'ObservationSampleRateHz',post.SampleRateHz,'ReceivedGridSHA256',capture.ReceivedGridSHA256, ...
        'DataTransmissionIdentity',identity,'CSITransmissionReceipt',emissionReceipt, ...
        'PhysicalConfigurationEpoch',owner.Physical.ConfigurationEpoch, ...
        'DMRSPilotIndices',capture.DMRSPilotIndices,'DMRSPilotSymbols',capture.DMRSPilotSymbols, ...
        'CSIRSPilotIndices',r.CSIRSPilotIndices,'CSIRSPilotSymbols',r.CSIRSPilotSymbols, ...
        'CSIResourceID',r.ResourceID,'CSIResourceOrdinal0',r.ResourceOrdinal0, ...
        'DataMapEvidence',mapEvidence,'Reference',reference, ...
        'EstimationSupport',capture.EstimationSupport,'EvaluationSupport',capture.EvaluationSupport, ...
        'ReferenceUsedByReceiver',false,'AdditionalReceiverExecutions',0,'StatisticallyQualified',false);
    comparisons=localAppend(comparisons,result);
end
end

function binding=localReceiverPlaneBinding(input,post,item,source,identity,epoch)
% This is the ORIGINAL input already consumed by the receiver. Do not run
% compensation again, equate its bytes to post-ADC bytes, or infer a gain.
assert(isstruct(input) && isscalar(input) && all(isfield(input,{'Observation','GainCompensation'})) && ...
    isa(input.Observation,'sixgr.phy.waveform.WaveformObservationBuffer') && ...
    isscalar(input.Observation),'sixgr:truth:PairedReceiverInputRequired', ...
    'Retain the original decoder-input observation, not a hash supplied by a trial row.');
receiver=input.Observation; compensation=input.GainCompensation;
assert(receiver.isComplete() && receiver.StartSample==post.StartSample && ...
    receiver.EndSampleExclusive==post.EndSampleExclusive && receiver.SampleRateHz==post.SampleRateHz && ...
    receiver.NumReceiveAntennas==post.NumReceiveAntennas && ...
    isstruct(compensation) && isscalar(compensation) && ...
    all(isfield(compensation,{'Source','InputPlane','OutputPlane','StartSample','EndSampleExclusive', ...
    'ClippingReconstructed','QuantizationRemoved'})) && ...
    string(compensation.Source)=="actual_receiver_applied_analog_gain_trace_after_ADC" && ...
    string(compensation.InputPlane)=="actual_post_rx_rf_post_adc_samples" && ...
    string(compensation.OutputPlane)=="digital_gain_compensated_received_samples_before_fft" && ...
    compensation.StartSample==post.StartSample && compensation.EndSampleExclusive==post.EndSampleExclusive && ...
    ~compensation.ClippingReconstructed && ~compensation.QuantizationRemoved, ...
    'sixgr:truth:PairedReceiverPlaneBinding','Bind the executed shared gain transformation on the same sample window.');
planes=item.Planes; ids=string({planes.ReceiverID});
segments=planes(ids==source.ReceiverID+":post_rf").Segments;
executed=cell(size(segments)); next=post.StartSample;
for k=1:numel(segments)
    s=segments{k}; a=max(post.StartSample,s.StartSample); b=min(post.EndSampleExclusive,s.EndSampleExclusive);
    node=s.Execution.RX(string({s.Execution.RX.ID})==source.ReceiverID);
    assert(isscalar(node) && a==next && b>a && isfield(node.Replay,'AGCControlModel') && ...
        s.Execution.ConfigurationEpoch==epoch && s.Execution.SampleRateHz==post.SampleRateHz, ...
        'sixgr:truth:PairedReceiverPlaneBinding','Original gain executions must cover this receiver window once.');
    r=node.Replay; trace=struct();
    if string(r.AGCControlModel)~="disabled"
        assert(isfield(r,'AGCStreamTrace') && all(isfield(r.AGCStreamTrace, ...
            {'StartSample','EndSampleExclusive','AppliedGain_dB'})), ...
            'sixgr:truth:PairedReceiverPlaneBinding','No gain trace may be inferred from a summary or current RF config.');
        original=r.AGCStreamTrace;
        assert(original.StartSample==s.StartSample && original.EndSampleExclusive==s.EndSampleExclusive && ...
            numel(original.AppliedGain_dB)==s.EndSampleExclusive-s.StartSample && ...
            all(isfinite(original.AppliedGain_dB),'all'), ...
            'sixgr:truth:PairedReceiverPlaneBinding','Keep the original applied per-sample gain trace.');
        trace=struct('StartSample',original.StartSample,'EndSampleExclusive',original.EndSampleExclusive, ...
            'AppliedGain_dB',original.AppliedGain_dB);
    end
    executed{k}=struct('ExecutionStartSample',s.StartSample,'ExecutionEndSampleExclusive',s.EndSampleExclusive, ...
        'ObservationStartSample',a,'ObservationEndSampleExclusive',b, ...
        'ReceiverID',source.ReceiverID,'ConfigurationEpoch',s.Execution.ConfigurationEpoch, ...
        'SampleRateHz',s.Execution.SampleRateHz, ...
        'AGCControlModel',string(r.AGCControlModel),'OriginalGainTrace',trace);
    next=b;
end
assert(next==post.EndSampleExclusive,'sixgr:truth:PairedReceiverPlaneBinding','No missing receiver gain interval.');
binding=struct('Contract',"completed_shared_receiver_planes/v1", ...
    'Source',"original_completed_decoder_input_and_executed_post_ADC_gain_trace", ...
    'ReceiverWindowID',string(item.ID),'ReceiverID',source.ReceiverID,'TransmitterID',source.TransmitterID, ...
    'TransmissionID',identity.TransmissionID,'PostRFHashPlane',"actual_post_rx_rf_post_adc_samples", ...
    'PhysicalConfigurationEpoch',epoch, ...
    'PostRFSampleSHA256',post.sampleHash(),'ReceiverInput',sixgr.link.receivedWaveformEvidence(receiver), ...
    'GainCompensation',compensation,'OriginalGainExecutions',{executed}, ...
    'AdditionalReceiverExecutions',0);
end

function values=localAppend(values,value)
if isempty(values), values=value;
else, values(end+1)=value;
end
end

function [maps,evidence]=localDataMaps(prepared,projection,support)
tx=prepared.Tx; L=double(tx.PDSCH.NumLayers); amplitude=double(tx.PowerContext.AmplitudeScale);
validateattributes(amplitude,{'double'},{'scalar','finite','positive'});
assert(size(projection,1)==prepared.NumPhysicalTransmitAntennas && ...
    size(projection,2)==size(tx.Waveform,2) && all(isfinite(projection),'all'), ...
    'sixgr:truth:PairedDMRSMap','Use the original waveform-to-physical projection.');
Q=size(support,1); maps=complex(zeros(size(projection,1),L,Q));
b=tx.PrecoderBundle;
if isempty(b)
    assert(string(tx.PrecoderMode)=="explicit_identity_no_bundle" && size(tx.Waveform,2)==L, ...
        'sixgr:truth:PairedDMRSMap','Absent bundle is allowed only for the explicitly executed native identity mapping.');
    for q=1:Q, maps(:,:,q)=amplitude*projection; end
    native=struct('Mode',string(tx.PrecoderMode),'Matrix',eye(L));
else
    assert(isa(b,'sixgr.pdsch.PDSCHPrecoderBundle') && b.NLayerPorts==L && ...
        b.NPhysicalTxAntennas==size(projection,2),'sixgr:truth:PairedDMRSMap','Retain actual native mapping pages.');
    [~,trace]=b.apply(complex(zeros(L,Q)),floor(support(:,1)/12),support(:,2),'Domain','dmrs');
    for q=1:Q
        maps(:,:,q)=amplitude*projection*b.W(:,:,trace.PRG(q)+1,trace.SymbolGroup(q)+1);
    end
    native=struct('Mode',b.Mode,'BundleSHA256',b.ImmutableBundleDigest, ...
        'MatrixPages',b.W,'Trace',trace);
end
evidence=struct('TXAmplitudeScale',amplitude,'WaveformToPhysicalMatrix',projection, ...
    'Native',native,'Source',"actual_emitted_DMRS_mapping_pages_and_amplitude_not_fitted_channel");
end
