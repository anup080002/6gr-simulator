function T=txLinearReferenceInterval(receipt,base)
% Separate fixed-linear MODEL audit; never an actual RF/power replacement.
row=struct('EndpointID',"",'Direction',"",'StartSample',NaN,'EndSampleExclusive',NaN, ...
    'SampleRateHz',NaN,'SampleCount',NaN,'ConfigurationEpoch',NaN,'PhysicalPortCount',NaN, ...
    'OriginSample',NaN,'WaveformAmplitudeUnit',"",'NumericClass',"", ...
    'RegistrationSHA256',"",'StaticOperatorSHA256',"",'IntervalOperatorSHA256',"", ...
    'RFInputWaveformSHA256',"",'RFOutputWaveformSHA256',"", ...
    'OriginalInputChunkSHA256',"",'OriginalOutputChunkSHA256',"", ...
    'ModelInputSHA256',"",'ReferenceOutputSHA256',"",'ResidualSHA256',"", ...
    'ReferenceEnergy',NaN,'ActualAggregateOutputEnergy',NaN,'ResidualEnergy',NaN, ...
    'ReferenceResidualCrossEnergy',NaN,'PowerClosureRelativeError',NaN, ...
    'ReceiptJSON',"",'ReceiptSHA256',"",'OriginalOwnerBindingVerified',true, ...
    'PhysicalIntervalCommitted',true,'ReceiverEstimatorInput',false, ...
    'StandardizedPowerAccuracyQualified',false,'HardwareQualified',false, ...
    'ActualNonlinearPortAttribution',false,'AdditionalRFExecutions',0,'AdditionalChannelExecutions',0, ...
    'RequirementClass',"IMPLEMENTATION_POLICY",'Classification',"optional_research_experiment", ...
    'EnergyScope',"sum_squared_complex_samples_with_declared_amplitude_unit_not_hardware_joules", ...
    'Source',"committed_original_TX_RF_owner_fixed_linear_diagnostic_model");
T=struct2table(row); T=T([],:); if nargin==0, return; end
assert(isstruct(receipt)&&isscalar(receipt)&&isfield(receipt,'Adapter')&& ...
    istable(base)&&height(base)==1&&base.Role=="TX", ...
    'sixgr:truth:TXLinearReferenceMissing','Require a separate original TX model receipt and RF base interval.');
a=receipt.Adapter;
for name=["EndpointID","Direction","StartSample","EndSampleExclusive","SampleRateHz", ...
        "SampleCount","ConfigurationEpoch","PhysicalPortCount"]
    row.(name)=base.(name);
end
for name=["RegistrationSHA256","OriginalInputChunkSHA256","OriginalOutputChunkSHA256"]
    row.(name)=string(receipt.(name));
end
for name=["WaveformAmplitudeUnit","NumericClass","StaticOperatorSHA256","IntervalOperatorSHA256", ...
        "ModelInputSHA256","ReferenceOutputSHA256","ResidualSHA256"]
    row.(name)=string(a.(name));
end
for name=["OriginSample","ReferenceEnergy","ActualAggregateOutputEnergy","ResidualEnergy", ...
        "ReferenceResidualCrossEnergy","PowerClosureRelativeError"]
    row.(name)=a.(name);
end
row.RFInputWaveformSHA256=string(a.OriginalRFInputSHA256);
row.RFOutputWaveformSHA256=string(a.OriginalRFOutputSHA256);
row.ReceiptJSON=string(jsonencode(receipt));
row.ReceiptSHA256=string(sixgr.util.sha256Hex(unicode2native(char(row.ReceiptJSON),'UTF-8')));
T=struct2table(row);
end
