function target=exportIndependentPUCCHObservation(runFolder,cfg,h,planes,received,receiverInput,receiverTimingPrior)
% Preserve the completed gNB receive hypothesis and native samples for replay.
% No prepared UE transmission is required or used to establish presence.
target="";
if nargin<7, receiverTimingPrior=[]; end
if ~sixgr.util.persistenceEnabled() || ...
        ~logical(sixgr.util.structGet(cfg,'outputs.rawIQCaptureEnabled',false)) || ...
        ~logical(sixgr.util.structGet(cfg,'outputs.saveRawWaveforms',false)), return; end
assert(isa(h.Assignment,'sixgr.phy.pucch.PUCCHReceptionAssignment') && ...
    isscalar(h.Assignment) && isa(h.Context,'sixgr.phy.pucch.UCIReportContext') && ...
    isscalar(h.Context) && h.Assignment.ReportContextDigest==h.Context.Digest && ...
    received.AssignmentDigest==h.Assignment.Digest && ...
    received.ReportContextDigest==h.Context.Digest, ...
    'sixgr:truth:PUCCHCaptureIdentityMismatch', ...
    'Capture only the independently bound assignment, context and actual receiver result.');
validateattributes(h.ServingCell,{'numeric'},{'scalar','integer','positive','finite'});
validateattributes(h.UEIndex,{'numeric'},{'scalar','integer','positive','finite'});
if h.Assignment.Format==0
    acquiredSR=isempty(receiverTimingPrior) && h.Context.HARQACKBits==0 && h.Context.SRBits==1 && ...
        h.Context.CSIPart1Bits==0 && h.Context.CSIPart2Bits==0 && ...
        received.ReceiveTiming.TimingSource=="received_configured_SR_sequence_bounded_search";
    retainedPrior=isa(receiverTimingPrior,'sixgr.phy.sync.ReceivedULTimingReference') && ...
        isscalar(receiverTimingPrior) && ...
        received.ReceiveTiming.ReferenceAvailableAtSample==receiverTimingPrior.AvailableAtSample;
    assert(acquiredSR || retainedPrior,'sixgr:truth:PUCCHCaptureTimingPriorRequired', ...
        'Retain the actual Format-0 timing prior, or the standalone-SR acquisition inputs.');
end
ids=string({planes.ReceiverID});
wanted=["gnb_"+h.ServingCell+"_rx:pre_rf", ...
    "gnb_"+h.ServingCell+"_rx:post_rf","ue_"+h.UEIndex+":tx"];
samples=cell(1,3); observations=cell(1,3);
for k=1:3
    hit=find(ids==wanted(k));
    assert(isscalar(hit),'sixgr:truth:MissingPUCCHCapturePlane', ...
        'Require exactly one actual plane %s.',wanted(k));
    observation=planes(hit).Observation;
    assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && ...
        isscalar(observation),'sixgr:truth:InvalidPUCCHCapturePlane', ...
        'Retain the actual contiguous observation, not a reconstructed waveform.');
    samples{k}=observation.readComplete();
    observations{k}=observation;
end
post=observations{2};
assert(received.ReceiverObservationStartSample==post.StartSample && ...
    received.ReceiverObservationEndSampleExclusive==post.EndSampleExclusive && ...
    received.ReceiverObservationSampleRateHz==post.SampleRateHz, ...
    'sixgr:truth:PUCCHCaptureClockMismatch','Receiver-result clocks must bind the actual capture.');
assert(isa(receiverInput,'sixgr.phy.waveform.WaveformObservationBuffer') && ...
    isscalar(receiverInput),'sixgr:truth:InvalidPUCCHCapturePlane', ...
    'Capture the exact observation passed to the receiver, including applied digital gain compensation.');
receiverSamples=receiverInput.readComplete();
for other={observations{1},receiverInput}
    other=other{1};
    assert(other.StartSample==post.StartSample && ...
        other.EndSampleExclusive==post.EndSampleExclusive && ...
        other.SampleRateHz==post.SampleRateHz, ...
        'sixgr:truth:PUCCHCaptureClockMismatch','Do not align, pad or trim retained receiver observations.');
end
tx=observations{3};
assert(tx.SampleRateHz==post.SampleRateHz,'sixgr:truth:PUCCHCaptureClockMismatch', ...
    'TX audit may have different bounds, but must share the actual sample clock.');
layout=sixgr.report.resultLayout(runFolder);
folder=fullfile(layout.AirInterfaceMATDir,'ul_control_received_observations');
target=string(fullfile(folder,"pucch_rx_ue"+h.UEIndex+"_cell"+h.ServingCell+ ...
    "_"+post.StartSample+"_"+h.Context.Digest+".mat"));
assert(~isfile(target),'sixgr:truth:DuplicateULControlCapture', ...
    'Do not overwrite a prior physical observation.');
capture=struct('Source',"actual_shared_gNB_PUCCH_receiver_observation", ...
    'Scope',"native_received_control_replay_not_instrument_power_calibration", ...
    'Config',cfg,'Assignment',h.Assignment,'Context',h.Context, ...
    'ReceivedResult',received,'SampleRateHz',post.SampleRateHz, ...
    'StartSample',post.StartSample,'EndSampleExclusive',post.EndSampleExclusive, ...
    'ReceiverID',wanted(2),'RXBeforeRF',samples{1},'RXAfterRF',samples{2}, ...
    'ReceiverInputSamples',receiverSamples, ...
    'ReceiverTimingPrior',receiverTimingPrior, ...
    'ReceiverInputRole',"exact_observation_passed_to_receivePUCCHObservation", ...
    'TXAfterRFAudit',samples{3},'TXStartSample',tx.StartSample, ...
    'TXEndSampleExclusive',tx.EndSampleExclusive, ...
    'TransmitterSamplesRole',"audit_only_not_PUCCH_presence_or_decode_authority", ...
    'SampleScaling',"unchanged_native_shared_plane_samples", ...
    'AmplitudeCalibration',"not_asserted_by_capture_export", ...
    'QualificationPassed',false);
% Native post-RF samples may include AGC; do not label every plane sqrt(mW).
% Replay consumes ReceiverInputSamples, Config, Assignment, Context and the
% retained measured timing prior (empty for reference-based acquisition).
sixgr.util.matSave(target,struct('capture',capture),'UseArtifactStore',false,'ForceV73',true);
end
