function [state, row, reception, csi] = completeSharedCSIRSReception(state, item)
%COMPLETESHAREDCSIRSRECEPTION Receive one independently scheduled CSI-RS.
arguments
    state (1,1) struct
    item (1,1) struct
end
assert(string(item.Kind) == "CSIRS" && ...
    isfield(state,"SharedWaveformStream") && ...
    isa(state.SharedWaveformStream,"sixgr.truth.CoupledWaveformStream"), ...
    'sixgr:truth:InvalidSharedCSIRSCompletion', ...
    'CSI-RS completion belongs to the shared physical owner.');
assert(isfield(item,'ID') && isscalar(string(item.ID)) && ...
    ~ismissing(string(item.ID)) && strlength(strtrim(string(item.ID)))>0, ...
    'sixgr:truth:InvalidSharedCSIRSCompletion', ...
    'A completed CSI-RS reception must retain its actual parent receive-window ID.');
context = item.Context;
prepared = context.Prepared;
assert(string(sixgr.util.structGet(prepared,"ExecutionStage","")) == ...
    "csirs_waveform_prepared_not_received", ...
    'sixgr:truth:InvalidSharedCSIRSPreparation', ...
    'Receive only the retained independent CSI-RS preparation.');
identity=localReceiverIdentity(prepared,context,item.UE);

[post,pre,transmitted,replay,receiverObservation] = ...
    sixgr.truth.sharedObservationEvidence(item.Planes,prepared);
receiverInput = receiverObservation.readComplete();
physicalInput = pre.readComplete();
assert(isequal(size(receiverInput),size(physicalInput)), ...
    'sixgr:truth:CSIRSReceiverPlaneDimensions', ...
    'CSI-RS post-front-end and physical receive planes must share one window.');
searchWindow = [0 max(0,size(receiverInput,1)-prepared.NumSamples)];
reception = sixgr.phy.refsig.receiveCSIRSWaveform( ...
    prepared.Carrier,prepared.ReceiverConfig,receiverInput,physicalInput, ...
    searchWindow,replay);
[reception,measurementPlane]=sixgr.truth.bindSharedCSIRSMeasurementPlane( ...
    reception,item,replay,state.SharedWaveformStream);
[csi,reportInfo] = sixgr.phy.refsig.computeCSIRSFeedback( ...
    prepared.Carrier,prepared.ReceiverConfig,reception);
assert(~reportInfo.PDSCHDecodeAttempted && ...
    ~reportInfo.PDSCHResourceAllocationAttempted && ...
    ~reportInfo.DCIConsumed && ~reportInfo.HARQStateConsumed, ...
    'sixgr:truth:IndependentCSIRSReportConsumedDataState', ...
    'Independent CSI-RS reporting cannot consume data/control decoder state.');

context.UEIndex = double(item.UE);
trialStruct = sixgr.truth.buildIndependentCSIRSTrialRow( ...
    prepared.ReceiverConfig,prepared,reception,csi,context);
row = struct2table(trialStruct,"AsArray",true);
assert(isnumeric(row.UEIndex)&&isequal(row.UEIndex,identity.UEIndex)&& ...
    isnumeric(row.CellID)&&isequal(row.CellID,identity.ServingCell), ...
    'sixgr:truth:CSICompletionReceiverIdentity', ...
    'The completed row must retain the original prepared receiver and cell.');
if ismember('ServingCell',row.Properties.VariableNames)
    assert(isnumeric(row.ServingCell)&&isequal(row.ServingCell,identity.ServingCell), ...
        'sixgr:truth:CSICompletionReceiverIdentity','Never overwrite a conflicting original serving cell.');
else
    row.ServingCell=identity.ServingCell;
end
for name=string(fieldnames(measurementPlane)).'
    row.(name)=measurementPlane.(name);
end
% The completed parent owns the receive-window identity. Its planes need not
% carry an ID, and a measurement digest is not a substitute for this window.
% Retain it even when private selection-quality scoring is disabled.
row.ReceiverWindowID = string(item.ID);
row=sixgr.truth.bindSharedRFExecutionEvidence(row,item.Planes,true);
receivedEvidence=sixgr.link.receivedWaveformEvidence(receiverObservation);
for name=string(fieldnames(receivedEvidence)).'
    row.(name)=receivedEvidence.(name);
end
row.PhysicalMeasurementObservationSHA256=pre.sampleHash();
row.PhysicalMeasurementObservationHashPlane=measurementPlane.PhysicalMeasurementReferencePlane;
% Execute only after practical CSI reception/report calculation. This
% measures the actual transmitter chain; it never claims RX-pilot EVM.
[paired,fullTX]=sixgr.phy.refsig.pairCSIRSTransmitterSymbols(prepared,transmitted);
% This post-receiver diagnostic uses the COMPLETE original TX grid, never
% sparse EVM pairs or a modeled/isolated logical-port waveform. It cannot
% enter practical CSI estimation, reporting, resource choice or scheduling.
row=localProjectedAttenuation(row,prepared,reception,fullTX,measurementPlane,item);
% state.RunFolder belongs to air_interface in a full bundle. Paired sample
% references are relative to the canonical RUN root, including control/CSV
% mirrors; never add air_interface twice or search outside this run.
storageRoot=string(sixgr.util.structGet(prepared.ReceiverConfig,'run.rootRunFolder',''));
assert(isscalar(storageRoot) && ~ismissing(storageRoot) && strlength(strtrim(storageRoot))>0, ...
    'sixgr:truth:MissingCSIRSArtifactRunRoot', ...
    'Completed CSI-RS sample storage requires the configured run.rootRunFolder.');
% EVM pairs and a channel-estimate MAT do not retain the receiver's input.
% When raw IQ capture is enabled, keep both actual synchronization planes
% losslessly for independent receiver replay. This runs after CSI selection
% and cannot supply an injected delay/CFO or noiseless channel to the UE.
if sixgr.util.persistenceEnabled() && ...
        logical(sixgr.util.structGet(prepared.ReceiverConfig,'outputs.rawIQCaptureEnabled',false)) && ...
        logical(sixgr.util.structGet(prepared.ReceiverConfig,'outputs.saveRawWaveforms',false))
    for prefix=["Receiver","PhysicalMeasurement"]
        samples=receiverInput;
        if prefix=="PhysicalMeasurement", samples=physicalInput; end
        receipt=sixgr.phy.waveform.CompletedSampleArchive.write(storageRoot,samples);
        assert(receipt.Manifest.SampleSHA256==row.(prefix+"ObservationSHA256"), ...
            'sixgr:truth:CSIRSObservationArchiveIdentity', ...
            'The immutable CSI-RS archive must match the exact received plane.');
        row.(prefix+"ObservationArchiveFile")=string(receipt.RelativePath);
        row.(prefix+"ObservationArchiveFileSHA256")=string(receipt.FileSHA256);
        row.(prefix+"ObservationArchiveReceiptJSON")=string(jsonencode(receipt));
    end
end
[desired,channelSource,channelCaptures]=sixgr.truth.sharedLinkScoringObservation( ...
    item.Planes,prepared,context.DesiredReferencePlane);
row = sixgr.truth.bindIndependentCSIRSClock( ...
    row,prepared,post,state.SharedWaveformStream.Events.NextSampleIndex, ...
    state.SharedWaveformStream.Physical.ConfigurationEpoch);
if isfield(context,'PopulationIdentity')
    % Bind the queue's frozen population to an actual completed transmission,
    % before either channel/selection archive becomes immutable. Later live
    % sweep/configuration state is not the identity of this observation.
    records=state.SharedWaveformStream.CSIRSTransmissions;
    hit=find(string({records.ComponentID})==string(context.ComponentID));
    assert(isscalar(hit),'sixgr:truth:CSIObservationPopulationReceipt', ...
        'A completed CSI observation must match exactly one actual TX receipt.');
    row=sixgr.truth.bindCSIObservationPopulation( ...
        row,context.PopulationIdentity,records(hit),string(context.ComponentID));
end
% Post-receiver audit only: one original isolation proof followed, when
% supported, by the recorded pre-RF operator on the same executed desired
% contribution. No reference is fed to Hest, reporting or the scheduler.
% A composite multiport/nonlinear LINK is not a port-3000 reference; that
% missing attribution remains an explicit unavailable diagnostic.
[powerComparison,isolation]=sixgr.truth.scoreSharedCSIRSPower( ...
    item,reception,desired,channelSource,replay,state.SharedWaveformStream);
for field=string(fieldnames(powerComparison)).'
    row.(field)=powerComparison.(field);
end
row.CSIRSReferenceIsolationAvailable=isolation.Available;
row.CSIRSReferenceIsolationStatus=string(isolation.Status);
row.CSIRSReferenceIsolationEvidenceJSON=string(jsonencode(isolation));
row.CSIRSReferenceIsolationEvidenceSHA256=sixgr.util.sha256Hex(char(row.CSIRSReferenceIsolationEvidenceJSON));
row.CSIRSReferenceIsolationErrorIdentifier=string(isolation.ErrorIdentifier);
% Separate optional MODEL comparison for every original resource/port 3000.
% This does not turn the aggregate nonlinear link into isolated port truth.
modelComparison=sixgr.truth.scoreSharedCSIRSLinearPortModel( ...
    item,reception,desired,channelSource,replay,state.SharedWaveformStream);
receivedEVM=sixgr.truth.scoreSharedCSIRSReceivedEVM( ...
    item,reception,desired,channelSource,replay,state.SharedWaveformStream);
for field=string(fieldnames(modelComparison)).'
    row.(field)=modelComparison.(field);
end
if logical(sixgr.util.structGet(prepared.ReceiverConfig,'measurements.csiSelectionQuality.Enabled',false))
    [row,selectionReference]=sixgr.truth.exportSharedCSIRSChannelEstimate( ...
        storageRoot,row,prepared,reception,channelSource,channelCaptures);
    row=sixgr.truth.bindSharedCSISelectionQuality( ...
        storageRoot,row,prepared,reception,csi,item.Planes,selectionReference,item.ID);
else
    row=sixgr.truth.exportSharedCSIRSChannelEstimate( ...
        storageRoot,row,prepared,reception,channelSource,channelCaptures);
end
row=sixgr.report.retainControlEVMPairs(storageRoot,row,paired);
row=sixgr.report.retainCSIRSReceivedEVMPairs(storageRoot,row,receivedEVM.Pairs,receivedEVM.Metrics);
row=sixgr.report.exportCSIRSReceivedEVMPairs(storageRoot,row);
row=sixgr.truth.DLMeasurementInstallation.stamp(state,row,prepared.ReceiverConfig,item.UE,"CSI-RS");
state = sixgr.truth.CoupledTruthRuntime.applyCSIRSTrial(state,item.UE,row);
end

function identity=localReceiverIdentity(prepared,context,ue)
cfg=prepared.ReceiverConfig;
originalUE=sixgr.util.structGet(cfg,'lls6g.userContext.UEIndex',NaN);
originalCell=sixgr.util.structGet(cfg,'lls6g.userContext.RuntimeServingCell',NaN);
queuedUE=sixgr.util.structGet(context,'UEIndex',NaN);
queuedCell=sixgr.util.structGet(context,'ServingCell',NaN);
for value={ue,originalUE,originalCell,queuedUE,queuedCell}
    v=value{1};
    assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&isfinite(v)&&v>=1&&v==fix(v), ...
        'sixgr:truth:CSICompletionReceiverIdentity', ...
        'Require original positive-integer prepared and queued receiver identities.');
end
assert(originalUE==ue&&queuedUE==ue&&queuedCell==originalCell, ...
    'sixgr:truth:CSICompletionReceiverIdentity', ...
    'Prepared receiver identity must match its queued completion, not a later serving selection.');
identity=struct('UEIndex',double(originalUE),'ServingCell',double(originalCell));
end

function row=localProjectedAttenuation(row,p,reception,tx,plane,item)
id='sixgr:truth:CSIRSProjectedAttenuationBinding';
obs=reception.CSIRSObservation;
token=string(reception.PhysicalMeasurementDemodulationReceiptJSON);
assert(isscalar(token)&&strlength(token)>0&& ...
    string(reception.PhysicalMeasurementDemodulationReceiptSHA256)== ...
    string(sixgr.util.sha256Hex(char(token))),id,'Original RX demodulation receipt changed.');
r=jsondecode(token);
bindingToken=string(plane.PhysicalMeasurementPlaneBindingJSON);
assert(string(plane.PhysicalMeasurementPlaneBindingSHA256)== ...
    string(sixgr.util.sha256Hex(char(bindingToken))),id,'Original RX plane binding changed.');
b=jsondecode(bindingToken);
assert(any(string(r.ContractVersion)==["sixgr.csirs.physical_demodulation/v1","sixgr.csirs.physical_demodulation/v2"])&& ...
    string(r.InputPlane)=="supplied_pre_composite_receiver_front_end_capture"&& ...
    string(b.ReceiverWindowID)==string(item.ID)&&string(b.OriginalInputSHA256)==string(r.InputSHA256)&& ...
    string(b.OriginalDemodulationReceiptSHA256)==string(reception.PhysicalMeasurementDemodulationReceiptSHA256)&& ...
    b.ObservationStartSample==p.ReceiveStartSample&&b.ObservationEndSampleExclusive==p.ReceiveEndSampleExclusive&& ...
    b.SampleRateHz==p.SampleRateHz,id,'Retain the exact original receiver/window/plane and clock.');
assert(string(tx.Source)=="actual_complete_post_TX_RF_grid_all_physical_columns"&& ...
    islogical(tx.PreRFZeroPositionsRetained)&&isscalar(tx.PreRFZeroPositionsRetained)&&tx.PreRFZeroPositionsRetained&& ...
    tx.ObservationStartSample==p.TransmitStartSample&& ...
    tx.ObservationEndSampleExclusive==p.TransmitStartSample+p.NumSamples&&tx.SampleRateHz==p.SampleRateHz&& ...
    isequal(size(tx.Grid),size(p.Tx.Grid))&& ...
    isequal(tx.PhysicalColumnIndices0,0:size(p.TransmitSamples,2)-1)&& ...
    string(tx.GridSHA256)==sixgr.phy.waveform.WaveformHash.runtimeArray(tx.Grid)&& ...
    string(tx.OFDMInfo.GridSHA256)==sixgr.phy.waveform.WaveformHash.numeric(tx.Grid)&& ...
    tx.OFDMInfo.SampleRate==p.SampleRateHz&&tx.OFDMInfo.Nfft==r.FFTSupport.Nfft&& ...
    tx.OFDMInfo.Nfft==obs.MeasurementFFTSize,id, ...
    'Use every original physical TX column, complete actual grid and original native FFT units.');
unit=string(p.PowerContext.WaveformAmplitudeUnit);
assert(isscalar(unit)&&unit==string(r.WaveformAmplitudeUnit),id,'Original TX/RX waveform units differ.');
resources=p.Tx.CSIRSInfo.Resources; measured=obs.MeasurementPhysicalResources;
recorded=r.Resources; if iscell(recorded), recorded=vertcat(recorded{:}); end
assert(isstruct(resources)&&~isempty(resources)&&iscell(measured)&&numel(resources)==numel(measured)&& ...
    numel(recorded)==numel(resources)&& ...
    string(obs.MeasurementPhysicalResourcesJSON)==string(jsonencode(sixgr.util.jsonSafeValue(measured))),id, ...
    'Retain every original resource in order, including unavailable measurements.');
assert(isnumeric([resources.ResourceID])&&all(isfinite([resources.ResourceID]))&& ...
    numel(unique([resources.ResourceID]))==numel(resources)&& ...
    isequal(double([recorded.ResourceID]),double([resources.ResourceID]))&& ...
    isequal(double([recorded.ResourceOrdinal0]),0:numel(resources)-1)&&r.ResourceSetID==row.ResourceSetID,id, ...
    'Original resource/set/ordinal identities disagree.');
evidence=struct('ContractVersion',"sixgr.csirs.shared_projected_attenuation/v1", ...
    'Scope',"post_TX_RF_to_pre_RX_RF_CDM_projected_effective_attenuation", ...
    'ReceiverWindowID',string(item.ID),'ParentComponentID',string(item.Context.ComponentID), ...
    'TransmitterPlane',string(item.Context.TransmitterPlane),'ReceiverID',string(b.ReceiverID), ...
    'ResourceSetID',r.ResourceSetID,'ResourceIDs',double([resources.ResourceID]), ...
    'TXObservationSHA256',string(tx.ObservationSHA256),'TXGridSHA256',string(tx.GridSHA256), ...
    'TXStartSample',tx.ObservationStartSample,'TXEndSampleExclusive',tx.ObservationEndSampleExclusive, ...
    'RXObservationSHA256',string(r.InputSHA256),'RXStartSample',b.ObservationStartSample, ...
    'RXEndSampleExclusive',b.ObservationEndSampleExclusive,'SampleRateHz',p.SampleRateHz, ...
    'RXPlane',string(plane.PhysicalMeasurementReferencePlane), ...
    'OriginalRXDemodulationReceiptSHA256',string(reception.PhysicalMeasurementDemodulationReceiptSHA256), ...
    'OriginalRXPlaneBindingSHA256',string(plane.PhysicalMeasurementPlaneBindingSHA256), ...
    'OriginalMeasurementResourcesSHA256',sixgr.util.sha256Hex(char(obs.MeasurementPhysicalResourcesJSON)), ...
    'WaveformAmplitudeUnit',unit,'PhysicalTransmitColumnIndices0',tx.PhysicalColumnIndices0, ...
    'ReceiverUsesReference',false,'AdditionalOFDMDemodulations',0, ...
    'AdditionalRFExecutions',0,'AdditionalChannelExecutions',0, ...
    'UniqueNonlinearPortAttributionQualified',false,'StandardizedPathlossQualified',false, ...
    'IndependentAccuracyQualified',false,'ResourceComparisons',{cell(numel(resources),1)});
available=false(numel(resources),1); K=12*double(p.Carrier.NSizeGrid); L=double(p.Carrier.SymbolsPerSlot);
for k=1:numel(resources)
    a=resources(k); recordedResource=recorded(k); m=measured{k};
    assert(isnumeric(a.Indices)&&isreal(a.Indices)&&all(isfinite(a.Indices),'all')&& ...
        all(a.Indices==fix(a.Indices),'all')&&all(a.Indices>=1&a.Indices<=K*L*a.NumPorts,'all')&& ...
        numel(a.Indices)==numel(a.Symbols)&& ...
        string(recordedResource.LogicalPilotIndicesSHA256)==sixgr.phy.waveform.WaveformHash.runtimeArray(a.Indices)&& ...
        string(recordedResource.LogicalPilotSymbolsSHA256)==sixgr.phy.waveform.WaveformHash.runtimeArray(a.Symbols),id, ...
        'Do not regenerate or replace original resource pilot operands.');
    q=struct('Available',false,'Status',"unavailable_original_resource_measurement", ...
        'EffectiveAttenuation_dB',NaN,'TransmitProjectedPower_dBm',NaN,'SelectedReceivedPower_dBm',NaN, ...
        'SelectedReceiveColumn1',NaN);
    if ~isempty(m)&&isstruct(m)&&isscalar(m)&&isfield(m,'ResourceID')
        assert(isnumeric(m.ResourceID)&&isreal(m.ResourceID)&&isscalar(m.ResourceID)&& ...
            m.ResourceID==a.ResourceID,id,'Original measured resource ID changed.');
        if plane.PhysicalMeasurementPlaneBindingAvailable
            reference=nrResourceGrid(p.Carrier,a.NumPorts); reference(a.Indices)=a.Symbols;
            q=sixgr.phy.refsig.projectCSIRSTransmitAttenuation( ...
                p.Carrier,tx.Grid,tx.OFDMInfo.Nfft,reference,m,unit);
        else
            q.Status="unavailable_original_physical_measurement_plane_binding";
        end
    end
    q.ResourceID=a.ResourceID; q.ResourceOrdinal0=k-1; q.ResourceSetID=r.ResourceSetID;
    q.ReferencePort=3000;
    evidence.ResourceComparisons{k}=q; available(k)=q.Available;
end
row.CSIRSTransmitProjectedAttenuationAvailable=any(available);
row.CSIRSTransmitProjectedAttenuationStatus="unavailable_original_projected_power_population";
if all(available), row.CSIRSTransmitProjectedAttenuationStatus="available_all_original_resources";
elseif any(available), row.CSIRSTransmitProjectedAttenuationStatus="available_partial_original_resources"; end
row.CSIRSTransmitProjectedAttenuationJSON=string(jsonencode(sixgr.util.jsonSafeValue(evidence)));
row.CSIRSTransmitProjectedAttenuationSHA256=sixgr.util.sha256Hex(char(row.CSIRSTransmitProjectedAttenuationJSON));
end
