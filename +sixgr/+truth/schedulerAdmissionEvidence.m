function row=schedulerAdmissionEvidence(state,cfg,ue,direction)
% Snapshot the actual input to scheduling, not a promised/decoded grant.
direction=upper(string(direction));
assert(isscalar(direction)&&ismember(direction,["DL","UL"]), ...
    'sixgr:truth:InvalidAdmissionDirection','Admission direction must be DL or UL.');
uid=double(ue.UEIndex);
queue=double(state.(direction+"QueueBits")(uid));
trafficDirection=upper(string(sixgr.util.structGet(state,'Traffic.FlowDirection',"")));
trafficConfigured=NaN;
if ismember(trafficDirection,["DL","UL","BIDIR"])
    trafficConfigured=double(ismember(trafficDirection,[direction,"BIDIR"]));
end
hasRetx=logical(ue.HasPendingRetransmission);
harqEnabled=logical(sixgr.util.structGet(cfg,'mac.harq.enable',false));
hasFree=NaN; harqStatus="not_required_by_configured_policy";
if harqEnabled
    entity=state.(direction+"Harq");
    % Read-only query: never allocate/release a process to build diagnostics.
    hasFree=double(entity.hasFreeProcess(ue.RNTI,ue.FeedbackKnownAtSlot-1));
    harqStatus="actual_process_state_before_scheduler_selection";
end
controlSlot=double(sixgr.util.structGet(state,'TimingControlAbsoluteSlot0Based',NaN))+1;
if ~isfinite(controlSlot), controlSlot=double(ue.FeedbackKnownAtSlot); end
dataSlot=double(state.CurrentSlot);
reason=string(ue.SchedulingBlockReason);
if ~ue.HasTrafficDemand
    reason="no_queued_bytes_or_pending_retransmission";
    if trafficConfigured==0, reason="traffic_direction_not_configured_and_no_pending_demand"; end
end
if ue.Active, reason="passed_traffic_and_reference_admission"; end
row=struct('Direction',direction,'UEIndex',uid,'RNTI',double(ue.RNTI), ...
    'SweepPointIndex',double(sixgr.util.structGet(state,'CurrentSweepPointIndex',NaN)), ...
    'ConfiguredSNR_dB',double(sixgr.util.structGet(state,'CurrentSNR_dB',NaN)), ...
    'ServingCell',double(ue.ServingCell),'ControlSlot',controlSlot, ...
    'ScheduledDataSlot',dataSlot,'SchedulingKnowledgeSlot',double(ue.FeedbackKnownAtSlot), ...
    'TrafficKnowledgeThroughSlot',double(sixgr.util.structGet(state, ...
        'PlanningTrafficThroughSlot',ue.FeedbackKnownAtSlot)), ...
    'SlotNumbering',"one_based_absolute_carrier_slot", ...
    'TrafficDirectionConfigured',trafficConfigured,'TrafficConfiguredDirection',trafficDirection, ...
    'TrafficConfigurationScope',"resolved_run_flow_direction_not_future_arrivals", ...
    'QueueBits',queue,'QueueBytes',floor(max(0,queue)/8), ...
    'SchedulerBufferBytes',double(ue.(direction+"BufferBytes")), ...
    'HasPendingRetransmission',hasRetx,'HasTrafficDemand',logical(ue.HasTrafficDemand), ...
    'AccessState',string(ue.AccessState),'ControlEligible',logical(ue.ControlEligible), ...
    'ReferenceEligible',logical(ue.SchedulingEligible), ...
    'ReferenceBlockReason',string(ue.SchedulingBlockReason), ...
    'SRSRequired',logical(ue.SRSRequired),'SRSCausalUsable',double(ue.SRSCausalUsable), ...
    'SRSCausalStatus',string(ue.SRSCausalStatus),'SRSMeasurementID',string(ue.SRSCausalMeasurementId), ...
    'CandidateRank',double(ue.NumLayers),'RankAuthority',string(ue.RankAuthority), ...
    'FeedbackValid',logical(ue.FeedbackValid),'FeedbackSourceSlot',double(ue.FeedbackSourceSlot), ...
    'FeedbackDeliveredSlot',double(ue.FeedbackDeliveredSlot),'FeedbackStatus',string(ue.CausalFeedbackStatus), ...
    'CausalFeedbackUsable',logical(ue.CausalFeedbackUsable), ...
    'HARQEnabled',harqEnabled,'HARQNewDataProcessAvailable',hasFree,'HARQStateSource',harqStatus, ...
    'ActiveAtSchedulerInput',logical(ue.Active),'AdmissionReason',reason, ...
    'CandidateGrantCount',0,'SchedulerDecisionReasons',"", ...
    'EvidenceRole',"actual_scheduler_input_not_received_DCI_or_data_execution", ...
    'ValueSource',"CoupledTruthRuntime.buildSchedulerUEState");
srsEvidence=sixgr.truth.projectAcceptedSRSDecisionEvidence(ue);
for name=string(fieldnames(srsEvidence)).'
    row.(name)=srsEvidence.(name);
end
end
