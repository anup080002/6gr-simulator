function proof=sharedSRSComponentIsolation(item,input,owner,windows)
% Join the ORIGINAL completed owner planes to exact emitted-component proof.
% POST-reception audit only. No inferred component hash or replacement IQ.
id='sixgr:truth:SRSIsolationOwnerIdentity';
assert(isa(owner,'sixgr.truth.CoupledWaveformStream') && ...
    string(item.Kind)=="SRS" && isfield(item.Context,'SRSComponentBinding'),id, ...
    'Retain the original completed SRS owner and emitted component binding.');
p=input.Prepared; b=item.Context.SRSComponentBinding;
assert(isa(p,'sixgr.link.PreparedUplinkControlTransmission') && p.Channel=="SRS" && ...
    isequaln(p,item.Context.Prepared) && ...
    string(b.ContractVersion)=="sixgr.truth.emitted_SRS_component/v1" && ...
    string(b.ComponentID)==string(item.ID) && b.UE==item.UE && ...
    b.StartSample==p.StartSample && b.EndSampleExclusive==p.EndSampleExclusive && ...
    b.SampleRateHz==p.SampleRateHz && b.ConfigurationEpoch==owner.Physical.ConfigurationEpoch && ...
    owner.Events.NextSampleIndex>=b.EndSampleExclusive,id, ...
    'Do not replace the actual preparation, component, endpoint, clock or epoch.');
source=input.DesiredReferenceEvidence; desired=input.DesiredReferenceObservation;
ids=string({item.Planes.ReceiverID});
hit=find(ids==string(item.Context.DesiredReferencePlane));
received=find(ids==string(source.ReceiverID)+":post_rf");
assert(isscalar(hit) && isscalar(received) && ...
    item.Planes(hit).Observation==desired && ...
    desired.isComplete() && ...
    string(source.Source)=="actual_executed_link_contribution" && ...
    string(source.TransmitterID)==string(b.TransmitterID) && ...
    string(source.ReceiverID)==string(input.Replay.ReceiverID) && ...
    source.StartSample==desired.StartSample && source.EndSampleExclusive==desired.EndSampleExclusive && ...
    desired.SampleRateHz==b.SampleRateHz && ...
    ~source.ReceiverEstimatorInput && source.AdditionalRFExecutions==0 && source.AdditionalChannelExecutions==0,id, ...
    'Use these exact completed desired-link and practical receiver observation instances.');
% The practical receiver consumes the fifth sharedObservationEvidence output,
% not the raw post-ADC handle. Validate the receipt CREATED by that original
% digital calibration, preserving both planes even when gain is disabled.
raw=item.Planes(received).Observation; receiver=input.Observation;
gain=input.Replay.ReceiverGainCompensation;
assert(raw.isComplete() && receiver.isComplete() && ...
    raw.StartSample==receiver.StartSample && raw.EndSampleExclusive==receiver.EndSampleExclusive && ...
    raw.SampleRateHz==receiver.SampleRateHz && raw.NumReceiveAntennas==receiver.NumReceiveAntennas && ...
    string(gain.ContractVersion)=="sixgr.phy.rx.completed_gain_compensation/v1" && ...
    string(gain.Source)=="actual_receiver_applied_analog_gain_trace_after_ADC" && ...
    string(gain.InputPlane)=="actual_post_rx_rf_post_adc_samples" && ...
    string(gain.OutputPlane)=="digital_gain_compensated_received_samples_before_fft" && ...
    string(gain.ReceiverID)==string(source.ReceiverID) && ...
    gain.StartSample==raw.StartSample && gain.EndSampleExclusive==raw.EndSampleExclusive && ...
    gain.SampleRateHz==raw.SampleRateHz && gain.NumReceiveBranches==raw.NumReceiveAntennas && ...
    string(gain.InputSampleSHA256)==raw.sampleHash() && ...
    string(gain.OutputSampleSHA256)==receiver.sampleHash() && ...
    ~gain.ClippingReconstructed && ~gain.QuantizationRemoved,id, ...
    'Bind original raw post-ADC and actual receiver-input samples through the original compensation receipt.');
assert(all(windows(:,1)>=desired.StartSample) && ...
    all(windows(:,2)<=desired.EndSampleExclusive),id,'No unretained desired-link samples or padding.');
request=struct('TransmitterID',string(source.TransmitterID), ...
    'ReceiverID',string(source.ReceiverID),'LinkID',string(source.LinkID), ...
    'ComponentID',string(b.ComponentID),'ComponentSHA256',string(b.ComponentSHA256), ...
    'SampleRateHz',b.SampleRateHz,'ConfigurationEpoch',b.ConfigurationEpoch, ...
    'FFTIntervals',windows);
proof=sixgr.truth.proveSRSComponentIsolation(owner.Events.ExecutionTrace,request);
proof.ReceiverInputBinding=gain;
end
