function row=bindCSIObservationPopulation(row,population,txReceipt,componentID)
%BINDCSIOBSERVATIONPOPULATION Bind queued identity before immutable archives.
% The caller obtains txReceipt from the SAME owner's CSIRSTransmissions by
% item.Context.ComponentID. A queued context alone is not emission evidence.
% Never read later runtime point/config metadata to relabel an old capture.
arguments
    row table
    population (1,1) struct
    txReceipt (1,1) struct
    componentID (1,1) string
end
assert(height(row)==1 && all(isfield(population, ...
    {'Version','Source','Fields','Queue','SHA256'})) && ...
    string(population.Version)=="csi_observation_population/v1" && ...
    string(population.Source)=="configured_queue_context_not_emission_proof", ...
    'sixgr:truth:InvalidCSIObservationPopulation','Use one original queued population capsule.');
assert(string(population.SHA256)== ...
    string(sixgr.util.sha256Hex(jsonencode(rmfield(population,'SHA256')))), ...
    'sixgr:truth:CSIObservationPopulationDigest','The queued population capsule changed.');
q=population.Queue;
requiredReceipt=["ComponentID","SignalFamily","ServingCell","Slot", ...
    "FirstActiveSample","CommittedAtSample","EndSampleExclusive", ...
    "SampleRateHz","PhysicalConfigurationEpoch"];
requiredRow=["Slot","CellID","ObservationSampleRateHz","MeasurementClockEpoch", ...
    "MeasurementClockDomain","ObservationEndSampleExclusive","ResultAvailableAtSample"];
assert(all(isfield(txReceipt,requiredReceipt)) && ...
    all(ismember(requiredRow,string(row.Properties.VariableNames))) && ...
    all(isfield(q,{'SourceSlot','QueuedAtSample','ClockDomain','PhysicalConfigurationEpoch','SampleRateHz'})), ...
    'sixgr:truth:CSIObservationPopulationReceipt','Retain the actual TX receipt and completed receiver clock.');
assert(~ismissing(componentID) && strlength(strtrim(componentID))>0 && ...
    string(txReceipt.ComponentID)==componentID && string(txReceipt.SignalFamily)=="CSI-RS" && ...
    txReceipt.Slot==q.SourceSlot && row.Slot==q.SourceSlot && ...
    txReceipt.ServingCell==row.CellID && ...
    string(q.ClockDomain)=="shared_physical_sample_clock/v1" && ...
    string(row.MeasurementClockDomain)=="shared_receiver_sample_clock/v1" && ...
    txReceipt.PhysicalConfigurationEpoch==q.PhysicalConfigurationEpoch && ...
    row.MeasurementClockEpoch==q.PhysicalConfigurationEpoch && ...
    txReceipt.SampleRateHz==q.SampleRateHz && row.ObservationSampleRateHz==q.SampleRateHz, ...
    'sixgr:truth:CSIObservationPopulationReceipt','Queued context, TX receipt and receiver must identify one source occasion/clock.');
times=[q.QueuedAtSample txReceipt.FirstActiveSample txReceipt.EndSampleExclusive ...
    txReceipt.CommittedAtSample row.ObservationEndSampleExclusive row.ResultAvailableAtSample];
assert(all(isfinite(times)) && all(times>=0 & times==fix(times)) && ...
    q.QueuedAtSample<=txReceipt.FirstActiveSample && ...
    txReceipt.FirstActiveSample<txReceipt.EndSampleExclusive && ...
    txReceipt.CommittedAtSample==txReceipt.EndSampleExclusive && ...
    txReceipt.EndSampleExclusive<=row.ObservationEndSampleExclusive && ...
    row.ObservationEndSampleExclusive<=row.ResultAvailableAtSample, ...
    'sixgr:truth:CSIObservationPopulationReceipt','Require actual nonzero TX completion before receiver availability.');
fields=population.Fields;
names=["RunFolder","RunID","RunTag","ExecutionID","ConfigHash","ScenarioID", ...
    "RandomSeed","ChannelSeed","SweepPointIndex","ConfiguredSNR_dB"];
assert(isscalar(fields) && isstruct(fields) && ...
    isequal(sort(string(fieldnames(fields))),sort(names(:))), ...
    'sixgr:truth:InvalidCSIObservationPopulation','Use the declared configured-population fields, not private receiver inputs.');
for name=names
    row=localBind(row,name,fields.(name));
end
binding=struct('Source',"queued_population_matched_to_completed_same_owner_CSI_RS_TX_receipt", ...
    'ComponentID',componentID,'SourceSlot',double(txReceipt.Slot), ...
    'ServingCell',double(txReceipt.ServingCell), ...
    'FirstActiveSample',double(txReceipt.FirstActiveSample), ...
    'CommittedAtSample',double(txReceipt.CommittedAtSample), ...
    'PhysicalConfigurationEpoch',double(txReceipt.PhysicalConfigurationEpoch), ...
    'SampleRateHz',double(txReceipt.SampleRateHz), ...
    'ReceiverResultAvailableAtSample',double(row.ResultAvailableAtSample));
row=localBind(row,"CSIObservationPopulationJSON",string(jsonencode(population)));
row=localBind(row,"CSIObservationPopulationSHA256",string(population.SHA256));
row=localBind(row,"CSIObservationPopulationSource",string(population.Source));
row=localBind(row,"CSIObservationPopulationBindingJSON",string(jsonencode(binding)));
end

function row=localBind(row,name,value)
assert(isscalar(value) && (isstring(value) || isnumeric(value)), ...
    'sixgr:truth:InvalidCSIObservationPopulation','Population fields must retain scalar typed values.');
if ismember(name,string(row.Properties.VariableNames))
    existing=row.(name);
    if isstring(value)
        existing=string(existing);
        blank=isscalar(existing) && (ismissing(existing) || strlength(strtrim(existing))==0);
    else
        blank=isnumeric(existing) && isscalar(existing) && isnan(existing);
    end
    assert(blank || isequaln(existing,value), ...
        'sixgr:truth:CSIObservationPopulationConflict', ...
        'Existing CSI-RS %s conflicts with its immutable queued population.',name);
end
row.(name)=value;
end
