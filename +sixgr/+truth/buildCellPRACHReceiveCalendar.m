function calendar=buildCellPRACHReceiveCalendar(cfg,cellID,receiver)
% Original gNB common configuration -> independent Type-1 receive calendar.
% No UE attempt, decoded UE state, selected beam or transmitted preamble is
% an input. This is configuration/clock arithmetic, not a detection receipt.
assert(isstruct(receiver) && isscalar(receiver) && all(isfield(receiver, ...
    {'SampleRateHz','NumReceiveAntennas','FilterTailSamples','FilterDelaySamples'})), ...
    'sixgr:truth:CellPRACHReceiverRequired','Require the actual installed cell receiver layout and implementation delay.');
validateattributes(cellID,{'numeric'},{'scalar','integer','positive','finite'});
for name=["NumReceiveAntennas","FilterTailSamples","FilterDelaySamples"]
    validateattributes(receiver.(name),{'numeric'},{'scalar','real','integer','nonnegative','finite'});
end
assert(receiver.NumReceiveAntennas>0 && receiver.FilterTailSamples>=receiver.FilterDelaySamples, ...
    'sixgr:truth:CellPRACHReceiverRequired','Retain the complete configured receive/filter support.');
carrier=sixgr.phy.grid.makeCarrier(cfg);
tree=sixgr.rrc.asn1.buildBCCHDLSCHMessage(cfg);
serving=tree.message.c1.systemInformationBlockType1.servingCellConfigCommon;
ul=serving.uplinkConfigCommon.initialUplinkBWP;
rach=ul.rach_ConfigCommon; bwp=ul.genericParameters;
[start,sizeRB]=sixgr.bwop.RIVFDRA.decode(275,bwp.locationAndBandwidth);
scs=str2double(erase(string(bwp.subcarrierSpacing),"kHz")); cp="normal";
if isfield(bwp,'cyclicPrefix'), cp=string(bwp.cyclicPrefix); end
assert(start==carrier.NStartGrid && sizeRB==carrier.NSizeGrid && ...
    scs==carrier.SubcarrierSpacing && cp==string(carrier.CyclicPrefix), ...
    'sixgr:truth:CellPRACHInitialBWPUnsupported','The present native receiver requires the original common BWP aligned with its carrier.');
[prachSCS,scsSource]=sixgr.mac.ra.resolveDecodedPRACHSubcarrierSpacing(rach);
fdmNames=["one","two","four","eight"]; fdmValues=[1 2 4 8];
assert(ismember(string(rach.msg1FDM),fdmNames),'sixgr:truth:CellPRACHCommonMismatch','Invalid original msg1-FDM.');
fdm=fdmValues(fdmNames==string(rach.msg1FDM));
range=string(sixgr.util.structGet(cfg,'frequency.range_name',sixgr.util.structGet(cfg,'phy.prach.frequencyRange',"")));
native=sixgr.phy.frame.PRACHOccasionResolver.resolve( ...
    'FrequencyRange',range,'DuplexMode',sixgr.phy.frame.resolveDuplexMode(cfg), ...
    'ConfigurationIndex',rach.configurationIndex,'CarrierSubcarrierSpacingKHz',scs, ...
    'CarrierCyclicPrefix',cp,'NSizeGrid',sizeRB,'NStartGrid',start,'NCellID',carrier.NCellID, ...
    'PRACHSubcarrierSpacingKHz',prachSCS,'SequenceIndex',rach.rootSequenceIndex, ...
    'PreambleIndex',0,'RestrictedSet',rach.restrictedSet,'ZeroCorrelationZone',rach.zeroCorrelationZoneConfig, ...
    'Msg1FDM',fdm,'Msg1FrequencyStart',rach.msg1FrequencyStart);
timing=sixgr.phy.frame.SSBTimingResolver.resolveFromConfig(cfg);
burst=sixgr.phy.ia.SSBBurstPlan.fromConfig(cfg,timing);
assert(burst.SelectionSource=="configured_ssb_positions_in_burst", ...
    'sixgr:truth:CellPRACHCommonMismatch','Cell monitoring requires the complete explicit transmitted SSB bitmap.');
spec=sixgr.phy.frame.AbsoluteTime.resolveNumerology(struct('SCSKHz',timing.SSBSubcarrierSpacingKHz,'CyclicPrefix',"normal"));
active=burst.Rows(burst.Rows.Active,:); symbols=active.AbsoluteSymbol0;
starts=spec.SymbolStartTicks(symbols+1); stops=spec.SymbolStartTicks(symbols+5);
period=int64(burst.PeriodicityMs)*(sixgr.phy.frame.AbsoluteTime.TicksPerSecond/int64(1000));
assert(all(stops<=period),'sixgr:truth:CellPRACHCommonMismatch','Original SSB support must fit its installed period.');
bitmap=char(string(serving.ssb_PositionsInBurst.inOneGroup));
assert(isequal(find(bitmap(1:burst.Lmax)=='1')-1,reshape(burst.ActiveSSBIndices0Based,1,[])), ...
    'sixgr:truth:CellPRACHCommonMismatch','gNB SIB1 and original cell SSB bitmap disagree.');
ssb=struct('Source',"configured_cell_common",'PeriodTicks',period, ...
    'SubcarrierSpacingKHz',timing.SSBSubcarrierSpacingKHz, ...
    'Intervals',table(active.SSBIndex0,starts(:),stops(:), ...
        'VariableNames',{'SSBIndex0','StartTicks','EndTicksExclusive'}));
tdd=[]; if isfield(serving,'tdd_UL_DL_ConfigurationCommon'), tdd=serving.tdd_UL_DL_ConfigurationCommon; end
common=struct('Source',"configured_cell_common",'CarrierCyclicPrefix',cp, ...
    'TDDCommonIE',tdd,'Procedure',"type1_single_preamble",'ChannelAccessMode',"not_provided");
validity=sixgr.phy.ra.resolvePRACHCandidateValidity(native,common,ssb);
assert(all(validity.RepeatedValidity==validity.RepeatedValidity(:,1),'all'), ...
    'sixgr:truth:CellPRACHAssociationPatternUnsupported','The installed SSB association currently requires validity to repeat every native period.');
choices=["oneEighth","oneFourth","oneHalf","one","two","four","eight","sixteen"];
ratios=[1/8 1/4 1/2 1 2 4 8 16]; choice=string(rach.ssbPerRACHChoice);
assert(ismember(choice,choices),'sixgr:truth:CellPRACHCommonMismatch','Invalid original SSB/RO association choice.');
cb=str2double(erase(string(rach.cbPreamblesPerSSB),"n"));
total=64; if isfield(rach,'nPreambles'), total=rach.nPreambles; end
association=sixgr.mac.ra.resolveSSBPRACHAssociation(native,burst.ActiveSSBIndices0Based, ...
    ratios(choices==choice),cb,total,validity.RepeatedValidity(:,1));
[guard,guardSource]=sixgr.phy.sync.resolveTimingSearchGuard(cfg,receiver.SampleRateHz);
offsetPresent=isfield(serving,'n_TimingAdvanceOffset'); offset="";
if offsetPresent, offset=string(serving.n_TimingAdvanceOffset); end
clock=struct('CellID',cellID,'ConfigurationEpoch',cfg.rf.configurationEpoch, ...
    'SampleRateHz',receiver.SampleRateHz,'RadioFrameZeroSample',0, ...
    'ConfigurationAvailableAtSample',0,'TimingAdvanceOffsetPresent',offsetPresent, ...
    'TimingAdvanceOffset',offset,'SearchGuardSamples',guard, ...
    'FilterTailSamples',receiver.FilterTailSamples,'NumReceiveAntennas',receiver.NumReceiveAntennas,'ULCarrierID',0);
detector=struct('SequenceIndex',rach.rootSequenceIndex,'RestrictedSet',string(rach.restrictedSet), ...
    'ZeroCorrelationZone',rach.zeroCorrelationZoneConfig,'Msg1FDM',fdm, ...
    'PRACHConfigurationIndex',rach.configurationIndex,'FrequencyStart',rach.msg1FrequencyStart, ...
    'PRACHSubcarrierSpacing',prachSCS,'FrequencyRange',range, ...
    'CarrierSCSkHz',scs,'NSizeGrid',sizeRB,'NStartGrid',start,'NCellID',carrier.NCellID, ...
    'NumTxAntennas',1,'TargetFalseAlarmProbability', ...
        sixgr.util.structGet(cfg,'random_access.target_false_alarm_probability',NaN));
calendar=struct('ContractVersion',"cell_PRACH_receive_calendar/v1", ...
    'Source',"original_gNB_common_configuration",'CellID',cellID, ...
    'PhysicalCellID',carrier.NCellID,'Native',native,'Validity',validity, ...
    'Association',association,'Receiver',clock,'FilterDelaySamples',receiver.FilterDelaySamples, ...
    'ConfiguredSIB1Tree',tree,'SSBPlan',burst,'PRACHConfig',detector, ...
    'Msg1SCSSource',scsSource,'SearchGuardSource',guardSource, ...
    'Scope',"configured_receiver_calendar_not_transmission_or_detection", ...
    'UETransmissionRequired',false);
calendar.SHA256=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(calendar))));
end
