classdef SharedDLSCHOutcomeBinding
    % Implementation-policy audit of one completed, connected DL decoder.
    % Keep the decoder capsule immutable. TransportGoodput/v1 is a separate
    % unique-TB accounting receipt, not proof of feedback/application delivery.
    % No decoding, scheduling, waveform processing or credit update occurs.
    methods (Static)
        function anchor=capture(state,item,control,res,decoderTrial,receiver,replay)
            anchor=struct();
            if ~sixgr.truth.SharedDLSCHOutcomeBinding.requiresBinding(decoderTrial), return; end
            source=sixgr.truth.SharedDLSCHOutcomeBinding.owner(state,item,control,false);
            [original,decoder]=sixgr.truth.SharedDLSCHOutcomeBinding.validateDecoderRow(decoderTrial,res.HARQ);
            id='sixgr:truth:SharedDLSCHDecoderBinding';
            assert(decoder.NumCodewords==1 && decoder.Codewords{1}.CodewordIndex==0 && ...
                decoder.Mode=="receiver_owned_final" && decoder.AdditionalDecoderInvocationCount==0 && ...
                string(res.ExecutionStage)=="received_shared_stream_completed" && ...
                string(res.HARQ.SharedTransmissionID)==source.TransmissionIdentity.TransmissionID && ...
                string(res.HARQ.ReceivedAssignmentDigest)==source.ReceivedAssignmentDigest && ...
                string(decoder.ReceivedAssignmentDigest)==source.ReceivedAssignmentDigest,id, ...
                'This bridge requires the original singleton received-control decoder, not an aggregate alias.');
            p=item.Context.Prepared;
            assert(decoderTrial.Frame==p.RequestBinding.StartFrameIndex && ...
                decoderTrial.Slot==p.RequestBinding.StartSlotIndex && ...
                decoderTrial.Slot==source.SourceSlot && ...
                decoderTrial.Frame==source.SourceFrame && ...
                decoder.Codewords{1}.TransportBlockSize==source.TBSBits,id, ...
                'The decoder clock and coded population must match the original preparation.');
            sixgr.truth.validateSharedDataReceptionTX(state,res.HARQ,res.HARQ.GrantSnapshot, ...
                res.HARQ.TransportBlockBits,item.UE,'DL',source.SourceSlot);
            observed=sixgr.link.receivedWaveformEvidence(receiver);
            ids=string({item.Planes.ReceiverID});
            hit=find(ids=="ue_"+item.UE+"_rx:post_rf");
            assert(isscalar(hit),'sixgr:truth:SharedDLSCHReceiverBinding','Original UE post-RF plane is required.');
            raw=item.Planes(hit).Observation; gain=replay.ReceiverGainCompensation;
            assert(raw.isComplete() && receiver.isComplete() && ...
                string(gain.ContractVersion)=="sixgr.phy.rx.completed_gain_compensation/v1" && ...
                string(gain.ReceiverID)=="ue_"+item.UE+"_rx" && ...
                any(string(gain.Source)==["actual_receiver_applied_analog_gain_trace_after_ADC", ...
                    "actual_receiver_recorded_block_gain_after_ADC"]) && ...
                string(gain.InputPlane)=="actual_post_rx_rf_post_adc_samples" && ...
                string(gain.OutputPlane)=="digital_gain_compensated_received_samples_before_fft" && ...
                gain.StartSample==raw.StartSample && gain.EndSampleExclusive==raw.EndSampleExclusive && ...
                gain.SampleRateHz==raw.SampleRateHz && gain.NumReceiveBranches==raw.NumReceiveAntennas && ...
                string(gain.InputSampleSHA256)==raw.sampleHash() && ...
                string(gain.OutputSampleSHA256)==observed.ReceiverObservationSHA256 && ...
                receiver.StartSample==raw.StartSample && receiver.EndSampleExclusive==raw.EndSampleExclusive && ...
                receiver.SampleRateHz==raw.SampleRateHz && receiver.NumReceiveAntennas==raw.NumReceiveAntennas, ...
                'sixgr:truth:SharedDLSCHReceiverBinding','Join distinct original raw and receiver-input planes through the original compensation receipt.');
            timing=res.HARQ.ReceivedTimingEvidence;
            expected=sixgr.truth.receivedDataSymbolTiming(p,receiver,res.ReceiveTiming,timing.ResultAvailableAtSample);
            assert(isequaln(timing,expected) && timing.DataAbsoluteSlot==source.SourceSlot-1 && ...
                control.AvailableAtSample<=raw.EndSampleExclusive && ...
                raw.EndSampleExclusive<=timing.ResultAvailableAtSample && ...
                timing.ResultAvailableAtSample<=state.SharedWaveformStream.Events.NextSampleIndex, ...
                'sixgr:truth:SharedDLSCHClockBinding','Retain source-slot and actual completion clocks separately.');
            % The original decoder row may predate these shared-owner columns.
            % If it already has them, they must describe the same input.
            for name=string(fieldnames(observed)).'
                if ismember(name,string(decoderTrial.Properties.VariableNames))
                    assert(isequaln(decoderTrial.(name),observed.(name)), ...
                        'sixgr:truth:SharedDLSCHReceiverBinding','Original decoder input field %s disagrees.',name);
                end
            end
            anchor=struct('Version',"shared_dlsch_precommit_anchor/v1", ...
                'SourceIdentity',source,'OriginalFields',original, ...
                'OriginalSourceRow',decoder.SourceRow, ...
                'OriginalAggregateGoodBits',double(decoderTrial.GoodBits), ...
                'OriginalAggregateGoodput_Mbps',double(decoderTrial.Goodput_Mbps), ...
                'SuccessfulDecodedBits',decoder.SuccessfulDecodedBits, ...
                'CRCPass',decoder.CRCPass,'ReceiverInput',observed, ...
                'RawPostRFSampleSHA256',raw.sampleHash(),'ReceiverGainCompensation',gain, ...
                'ReceivedTiming',timing,'ReceiveTimingFields', ...
                    sixgr.truth.harqFeedbackReceiveTimingFields(res.HARQ,res.HARQ.GrantSnapshot,true), ...
                'BeforeCredit',sixgr.truth.SharedDLSCHOutcomeBinding.ledgerSnapshot( ...
                    sixgr.util.structGet(state,'TransportGoodputLedger',[])));
            anchor.SHA256=sixgr.truth.SharedDLSCHOutcomeBinding.hash(anchor);
        end

        function trial=bind(state,item,control,trial,anchor)
            id='sixgr:truth:SharedDLSCHFinalRowBinding';
            assert(isstruct(anchor)&&isscalar(anchor)&&isfield(anchor,'SHA256') && ...
                anchor.Version=="shared_dlsch_precommit_anchor/v1" && ...
                anchor.SHA256==sixgr.truth.SharedDLSCHOutcomeBinding.hash(rmfield(anchor,'SHA256')),id, ...
                'Use the unchanged pre-commit anchor from this completion.');
            source=sixgr.truth.SharedDLSCHOutcomeBinding.owner(state,item,control,true);
            assert(isequaln(source,anchor.SourceIdentity)&&istable(trial)&&height(trial)==1,id, ...
                'The original control, preparation and physical receipts cannot change during completion.');
            for name=string(anchor.OriginalFields.Properties.VariableNames)
                assert(ismember(name,string(trial.Properties.VariableNames)) && ...
                    isequaln(trial.(name),anchor.OriginalFields.(name)),id, ...
                    'The original final decoder field %s must survive unchanged.',name);
            end
            for name=string(fieldnames(anchor.ReceiverInput)).'
                assert(ismember(name,string(trial.Properties.VariableNames)) && ...
                    isequaln(trial.(name),anchor.ReceiverInput.(name)),id,'Final row changed receiver input %s.',name);
            end
            for name=string(fieldnames(anchor.ReceiveTimingFields)).'
                assert(ismember(name,string(trial.Properties.VariableNames)) && ...
                    isequaln(trial.(name),anchor.ReceiveTimingFields.(name)),id,'Final row changed receive clock %s.',name);
            end
            sixgr.truth.SharedDLSCHOutcomeBinding.validateFinalCRC(trial,anchor.CRCPass);
            assert(string(trial.Direction)=="DL" && trial.Frame==source.SourceFrame && trial.Slot==source.SourceSlot && ...
                trial.UEIndex==source.TransmissionIdentity.UEIndex && trial.RNTI==source.TransmissionIdentity.RNTI && ...
                string(trial.GrantContextId)==source.LogicalGrantContextID && ...
                string(trial.FrozenGrantContextId)==source.TransmissionIdentity.PHYGrantContextId && ...
                string(trial.ReceivedAssignmentDigest)==source.ReceivedAssignmentDigest && ...
                double(trial.TBSize_bits)==source.TBSBits && ...
                trial.HARQProcess==source.HARQProcess && trial.HARQNDI==source.NDI && ...
                trial.HARQRV==source.RV && trial.NDIEpoch==source.NDIEpoch && ...
                string(trial.TBId)==source.TBId && ...
                isequaln(trial.DecodedAttemptBits,anchor.OriginalAggregateGoodBits) && ...
                isequaln(trial.DecodedAttemptGoodput_Mbps,anchor.OriginalAggregateGoodput_Mbps),id, ...
                'Final identity/attempt bits must join the original source, not the callback slot or unique credit.');
            credit=sixgr.truth.SharedDLSCHOutcomeBinding.validateCredit(trial,anchor.BeforeCredit, ...
                sixgr.util.structGet(state,'TransportGoodputLedger',[]));
            evidence=struct('Version',"shared_dlsch_outcome_binding/v1", ...
                'Stage',"completed_shared_decoder_transport_credit_binding", ...
                'Source',"original_decoder_and_shared_completion_owner_receipts", ...
                'Scope',"connected_single_codeword_decoder_to_unique_TB_accounting_not_full_MAC", ...
                'DecoderSHA256',string(anchor.OriginalFields.DLSCHFinalOutcomeSHA256), ...
                'OriginalDecoderSourceRow',anchor.OriginalSourceRow, ...
                'SourceIdentity',source,'ReceiverInput',anchor.ReceiverInput, ...
                'RawPostRFSampleSHA256',anchor.RawPostRFSampleSHA256, ...
                'ReceiverGainCompensation',anchor.ReceiverGainCompensation, ...
                'ReceivedTiming',anchor.ReceivedTiming, ...
                'OriginalAggregateGoodBits',anchor.OriginalAggregateGoodBits, ...
                'SuccessfulDecodedBits',anchor.SuccessfulDecodedBits, ...
                'DecodedBitsScope',"this_decoder_attempt_not_unique_MAC_delivery", ...
                'CRCPass',anchor.CRCPass,'TransportCredit',credit, ...
                'OriginalDecoderTokenUnchanged',true,'OriginalOwnerJoinVerified',true, ...
                'AdditionalDecoderInvocations',0,'AdditionalCreditUpdates',0, ...
                'FeedbackTransmissionQualified',false,'ApplicationDeliveryQualified',false, ...
                'FullMACQualified',false,'StatisticalIndependenceClaimed',false);
            token=string(jsonencode(evidence));
            values=struct('SharedDLSCHOutcomeAvailable',true, ...
                'SharedDLSCHOutcomeStage',evidence.Stage,'SharedDLSCHOutcomeJSON',token, ...
                'SharedDLSCHOutcomeSHA256',string(sixgr.util.sha256Hex(char(token))), ...
                'SharedDLSCHOutcomeTransmissionID',source.TransmissionIdentity.TransmissionID, ...
                'SharedDLSCHOutcomeDecoderSHA256',evidence.DecoderSHA256, ...
                'SharedDLSCHOutcomeTransportCreditBound',credit.Available);
            for name=string(fieldnames(values)).'
                if ismember(name,string(trial.Properties.VariableNames))
                    assert(isequaln(trial.(name),values.(name)),id,'A shared decoder bridge cannot be replaced.');
                end
                trial.(name)=values.(name);
            end
        end

        function required=requiresBinding(trial)
            % Unavailable/no-decode outcomes are not decoder receipts. A
            % genuine completed decoder cannot silently lose its capsule.
            id='sixgr:truth:SharedDLSCHDecoderBinding'; required=false;
            assert(istable(trial)&&height(trial)<=1,id,'One shared event owns at most one decoder row.');
            if isempty(trial), return; end
            names=string(trial.Properties.VariableNames);
            flags=["Crash","CRCApplicable","DecodeAttempted","DLSCHDecodeAttempted"];
            completed=all(ismember([flags "CRCPass"],names));
            if completed
                values=zeros(1,numel(flags));
                for k=1:numel(flags)
                    value=trial.(flags(k));
                    assert((isnumeric(value)||islogical(value))&&isreal(value)&&isscalar(value)&& ...
                        (isnan(value)||any(value==[0 1])),id,'Invalid original receiver stage flag.');
                    values(k)=double(value);
                end
                crc=trial.CRCPass;
                assert((isnumeric(crc)||islogical(crc))&&isreal(crc)&&isscalar(crc)&& ...
                    (isnan(crc)||any(crc==[0 1])),id,'Invalid original decoder CRC.');
                completed=isequal(values,[0 1 1 1])&&any(crc==[0 1]);
            end
            if ismember('DLSCHFinalOutcomeAvailable',names)
                value=trial.DLSCHFinalOutcomeAvailable;
                assert((isnumeric(value)||islogical(value))&&isscalar(value)&&any(value==[0 1]),id, ...
                    'Final decoder availability must be explicit.');
                required=logical(value);
            end
            assert(required==completed,id, ...
                'Completed decoder evidence requires its final capsule; unavailable reception cannot claim one.');
            if ~required
                for name=["DLSCHFinalOutcomeJSON","DLSCHFinalOutcomeSHA256"]
                    if ismember(name,names)
                        value=string(trial.(name));
                        assert(isscalar(value)&&(ismissing(value)||strlength(value)==0),id, ...
                            'Unavailable decoding cannot carry a populated final capsule.');
                    end
                end
            end
        end

        function [original,decoder]=validateDecoderRow(trial,harq)
            % Pure lower boundary: codec/row integrity, NOT a shared-owner proof.
            id='sixgr:truth:SharedDLSCHDecoderBinding';
            names=["DLSCHFinalOutcomeAvailable","DLSCHFinalOutcomeStage", ...
                "DLSCHFinalOutcomeJSON","DLSCHFinalOutcomeSHA256","DLSCHSuccessfulDecodedBits", ...
                "DLSCHSuccessfulDecodedBitsScope","DLSCHAggregateGoodBitsPolicy"];
            assert(istable(trial)&&height(trial)==1&&all(ismember(names,string(trial.Properties.VariableNames))) && ...
                isequal(trial.DLSCHFinalOutcomeAvailable,true)&& ...
                isstruct(harq)&&isscalar(harq)&&all(isfield(harq, ...
                    {'FinalCodewordOutcome','FinalDecodedTransportBlocks','CombinedDecodeOK'})),id, ...
                'Require the original completed decoder row and selected per-codeword payloads.');
            selection=harq.FinalCodewordOutcome;
            if isfield(harq,'ReceivedAssignmentDigest')
                selection.ReceivedAssignmentDigest=string(harq.ReceivedAssignmentDigest);
            end
            [checked,decoder]=sixgr.link.bindDLSCHFinalOutcome(removevars(trial,cellstr(names)),selection);
            for name=names
                assert(isequaln(trial.(name),checked.(name)),id,'Decoder capsule/row contradiction in %s.',name);
            end
            payloads=harq.FinalDecodedTransportBlocks;
            verdict=harq.CombinedDecodeOK;
            assert(iscell(payloads)&&numel(payloads)==decoder.NumCodewords && ...
                (isnumeric(verdict)||islogical(verdict))&&isreal(verdict)&&isscalar(verdict)&& ...
                isfinite(verdict)&&any(verdict==[0 1])&& ...
                double(verdict)==double(decoder.CRCPass),id,'Final decoder population/verdict mismatch.');
            for k=1:decoder.NumCodewords
                bits=payloads{k}; word=decoder.Codewords{k};
                assert((isnumeric(bits)||islogical(bits))&&isreal(bits)&&isvector(bits)&& ...
                    all(bits(:)==0|bits(:)==1)&&numel(bits)==word.TransportBlockSize && ...
                    word.DecodedTransportBlockSHA256==string(sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(int8(bits(:)))), ...
                    id,'Selected payload does not match its original codeword receipt.');
            end
            original=trial(:,cellstr(names));
        end

        function snapshot=ledgerSnapshot(ledger)
            ledger=sixgr.truth.SharedDLSCHOutcomeBinding.ledger(ledger);
            snapshot=struct('Version',"transport_credit_ledger_fingerprint/v1", ...
                'EntryCount',numel(ledger.Key),'SHA256',sixgr.truth.SharedDLSCHOutcomeBinding.hash(ledger));
        end

        function validateFinalCRC(trial,expected)
            % Pure value boundary, also used by the completed-owner binding.
            id='sixgr:truth:SharedDLSCHFinalRowBinding';
            assert(istable(trial)&&height(trial)==1&&ismember('CRCPass',trial.Properties.VariableNames),id, ...
                'Require the original explicit completed decoder verdict.');
            value=trial.CRCPass;
            assert((isnumeric(value)||islogical(value))&&isreal(value)&&isscalar(value)&& ...
                isfinite(value)&&any(value==[0 1])&& ...
                (isnumeric(expected)||islogical(expected))&&isreal(expected)&&isscalar(expected)&& ...
                isfinite(expected)&&any(expected==[0 1])&&double(value)==double(expected),id, ...
                'Final CRC must be finite binary and equal the original decoder, not coerced to logical.');
        end

        function credit=validateCredit(trial,before,after)
            % Read-only lower accounting boundary; no physical-owner claim.
            id='sixgr:truth:SharedDLSCHTransportCredit';
            assert(istable(trial)&&height(trial)==1&&isstruct(before)&&isscalar(before)&& ...
                all(isfield(before,{'Version','EntryCount','SHA256'}))&& ...
                before.Version=="transport_credit_ledger_fingerprint/v1"&& ...
                isscalar(before.EntryCount)&&isfinite(before.EntryCount)&&before.EntryCount>=0&& ...
                before.EntryCount==fix(before.EntryCount)&&isscalar(string(before.SHA256))&&strlength(string(before.SHA256))==64,id, ...
                'Require an original pre-credit fingerprint and one final credit row.');
            retained={'UniqueDeliveredTBBits','FirstSuccessfulTBDelivery','TransportGoodputKey', ...
                'TransportGoodputStatus','TransportGoodputDefinition','TransportGoodputContract', ...
                'UniqueTransportGoodput_Mbps','GoodBits','Goodput_Mbps'};
            assert(all(ismember(retained,trial.Properties.VariableNames)),id, ...
                'All original completed credit columns must exist; never reconstruct missing producer credit.');
            first=trial.FirstSuccessfulTBDelivery;
            assert((isnumeric(first)||islogical(first))&&isreal(first)&&isscalar(first)&& ...
                isfinite(first)&&any(first==[0 1]),id,'The original first-delivery flag must be explicit finite binary.');
            bits=sixgr.kpi.transportGoodputBits(trial); % Validates; does not mutate/recredit the runtime ledger.
            assert(isequaln(double(trial.GoodBits),bits)&& ...
                isequaln(double(trial.Goodput_Mbps),double(trial.UniqueTransportGoodput_Mbps)),id, ...
                'Canonical GoodBits/rate must retain the actual unique-credit receipt.');
            after=sixgr.truth.SharedDLSCHOutcomeBinding.ledger(after);
            post=sixgr.truth.SharedDLSCHOutcomeBinding.ledgerSnapshot(after);
            status=string(trial.TransportGoodputStatus); key=string(trial.TransportGoodputKey);
            if ismissing(key), key=""; end
            known=any(status==["first_crc_success","repeated_crc_success_no_new_payload","crc_failure_no_delivery"]);
            hit=find(after.Key==key); delta=0;
            if status=="first_crc_success"
                assert(isscalar(hit)&&after.PayloadBits(hit)==bits,id,'First credit needs its unique actual target entry.');
                previous=after; previous.Key(hit)=[]; previous.PayloadBits(hit)=[];
                assert(isequaln(sixgr.truth.SharedDLSCHOutcomeBinding.ledgerSnapshot(previous),before),id, ...
                    'Exactly this target may be added by the completion.');
                delta=1;
            else
                assert(isequaln(post,before),id,'A failed, repeated or unavailable credit cannot alter the ledger.');
                if status=="repeated_crc_success_no_new_payload"
                    assert(isscalar(hit)&&after.PayloadBits(hit)==double(trial.TBSize_bits)&&bits==0,id, ...
                        'Repeated success requires the same prior logical TB and no second payload credit.');
                end
            end
            credit=struct('Contract',string(trial.TransportGoodputContract),'Available',known, ...
                'Status',status,'Key',key,'UniqueDeliveredTBBits',bits, ...
                'FirstSuccessfulTBDelivery',logical(trial.FirstSuccessfulTBDelivery), ...
                'Definition',string(trial.TransportGoodputDefinition), ...
                'BeforeLedger',before,'AfterLedger',post,'TargetEntryDelta',delta, ...
                'AccountingOnly',true,'ExecutionProof',false);
        end
    end

    methods (Static, Access=private)
        function source=owner(state,item,control,committed)
            id='sixgr:truth:SharedDLSCHOwnerRequired';
            assert(isstruct(state)&&isscalar(state)&&isfield(state,'SharedWaveformStream')&& ...
                isa(state.SharedWaveformStream,'sixgr.truth.CoupledWaveformStream'),id, ...
                'Use the original shared physical owner; declared codec/ledger fixtures are not execution proof.');
            owner=state.SharedWaveformStream;
            assert(~owner.Events.Faulted&&~owner.Physical.Faulted&& ...
                owner.Events.NextSampleIndex==owner.Physical.NextSampleIndex && ...
                isstruct(item)&&isscalar(item)&&string(item.Kind)=="PDSCH" && ...
                isa(item.Context.Prepared,'sixgr.link.PreparedDataTransmission'),id,'Require one completed original PDSCH item.');
            p=item.Context.Prepared; g=p.RequestBinding.Grant;
            identity=sixgr.truth.preparedDataTransmissionIdentity(p,item.UE);
            assert(p.Direction=="DL"&&isequaln(identity,item.Context.TransmissionIdentity)&& ...
                p.SampleRateHz==owner.SampleRateHz&&owner.Events.NextSampleIndex>=p.EndSampleExclusive,id, ...
                'The exact original preparation must have reached its end.');
            controls=sixgr.util.structGet(state,'SharedReceivedGrantControls',{});
            assert(isequal(control.Allowed,true)&&string(control.Key)==string(item.Context.Key)&& ...
                nnz(cellfun(@(x)isequaln(x,control),controls))==1&& ...
                nnz(cellfun(@(x)string(x.Key)==string(control.Key),controls))==1,id,'Use the exact retained received control.');
            sixgr.truth.bindReceivedPDCCHGrantEvidence(g,control.Grant);
            a=control.ReceivedAssignment;
            assert(string(a.Source)=="received_dci_bits_plus_installed_connected_context"&& ...
                string(a.AssignmentDigest)==sixgr.truth.SharedDLSCHOutcomeBinding.hash(orderfields(rmfield(a,'AssignmentDigest')))&& ...
                a.Direction=="DL"&&a.RNTI==identity.RNTI,id,'Received assignment identity must be original.');
            tx=owner.DataTransmissions; index=find(arrayfun(@(x)x.Identity.TransmissionID==identity.TransmissionID,tx));
            ledger=sixgr.util.structGet(state,'SharedDataTXLedger',{});
            hit=find(cellfun(@(x)x.Identity.TransmissionID==identity.TransmissionID,ledger));
            assert(isscalar(index)&&isscalar(hit),id,'Require original physical and MAC TX receipts.');
            physical=tx(index); mac=ledger{hit};
            assert(isequaln(physical.Identity,identity)&&isequaln(mac.Identity,identity)&& ...
                physical.FirstActiveSample==mac.FirstActiveSample&&physical.CommittedAtSample==mac.CommittedAtSample&& ...
                physical.CommittedAtSample==physical.FirstActiveSample+1&& ...
                physical.FirstActiveSample>=p.StartSample&&physical.FirstActiveSample<p.EndSampleExclusive&& ...
                isequal(mac.TransportBlockBits,int8(p.Tx.TransportBlock(:)))&& ...
                string(mac.Grant.PHYGrant.GrantContextId)==identity.PHYGrantContextId&& ...
                string(mac.Grant.GrantContextId)==string(g.GrantContextId),id,'Do not transplant a TX receipt or TB.');
            rx=sixgr.util.structGet(state,'SharedDataRXCommittedIDs',strings(0,1));
            assert(nnz(rx==identity.TransmissionID)==double(committed)&& ...
                ~any(sixgr.util.structGet(state,'SharedDataNoDecodeCommittedIDs',strings(0,1))==identity.TransmissionID),id, ...
                'Require the expected once-only RX commit boundary, not a no-decode disposition.');
            slot=double(p.RequestBinding.StartSlotIndex); frame=double(p.RequestBinding.StartFrameIndex);
            trace=state.SlotTraceTable; row=find(double(trace.CanonicalSlot)==slot);
            assert(isscalar(row)&&slot==double(p.ReceiverConfig.lls6g.runtime.AbsoluteSlotIndex0)+1&& ...
                slot==double(mac.Grant.Slot)&&frame==double(mac.Grant.Frame)&&a.DataAbsoluteSlot==slot-1&& ...
                slot<=state.CurrentSlot,id,'Preserve source-slot versus callback-clock coordinates.');
            h=mac.Grant.HARQ; tb=sixgr.truth.resolveGrantTransportBlockIdentity(mac.Grant);
            assert(strlength(tb)>0&&isscalar(h.NDIEpoch)&&isfinite(h.NDIEpoch),id,'Require actual logical TB generation identity.');
            source=struct('TransmissionIdentity',identity,'ReceiverWindowID',string(item.ID), ...
                'LogicalGrantContextID',string(g.GrantContextId),'ControlKey',string(control.Key), ...
                'ReceivedAssignmentDigest',string(a.AssignmentDigest),'ControlAvailableAtSample',control.AvailableAtSample, ...
                'SourceFrame',frame,'SourceSlot',slot,'SourceFrameLocal',double(trace.FrameLocal(row)), ...
                'PhysicalConfigurationEpoch',owner.Physical.ConfigurationEpoch, ...
                'FirstActiveSample',physical.FirstActiveSample,'TXCommittedAtSample',physical.CommittedAtSample, ...
                'TBSBits',double(numel(mac.TransportBlockBits)), ...
                'TBId',tb,'HARQProcess',double(h.HarqID),'NDI',double(h.NDI), ...
                'RV',double(h.RV),'NDIEpoch',double(h.NDIEpoch));
        end

        function value=ledger(value)
            if isempty(value), value=struct('Key',strings(0,1),'PayloadBits',zeros(0,1)); end
            id='sixgr:truth:SharedDLSCHTransportCredit';
            assert(isstruct(value)&&isscalar(value)&&all(isfield(value,{'Key','PayloadBits'}))&& ...
                isstring(value.Key)&&isnumeric(value.PayloadBits)&&isreal(value.PayloadBits)&& ...
                numel(value.Key)==numel(value.PayloadBits)&&all(~ismissing(value.Key))&& ...
                all(strlength(value.Key)>0)&&numel(unique(value.Key))==numel(value.Key)&& ...
                all(isfinite(value.PayloadBits)&value.PayloadBits>0&value.PayloadBits==fix(value.PayloadBits)),id, ...
                'Read the original unique-key/actual-payload ledger, never manufacture a target entry.');
            value=struct('Key',value.Key(:),'PayloadBits',double(value.PayloadBits(:)));
        end

        function sha=hash(value)
            sha=string(sixgr.util.sha256Hex(char(jsonencode(value))));
        end
    end
