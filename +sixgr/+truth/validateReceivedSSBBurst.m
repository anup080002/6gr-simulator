function indices=validateReceivedSSBBurst(cfg,slotIdx,received)
% Validate the complete original receiver population, not TX in slotIdx.
% A later SSB candidate belongs to the same burst-origin capture. Request
% identities remain distinct from decoded identities (which may be absent).
% This consistency check does not independently authenticate PHY execution;
% the shared owner retains the original completed observation separately.
id='sixgr:truth:ReceivedSSBBurstIdentity';
assert(isa(slotIdx,'double') && isreal(slotIdx) && isscalar(slotIdx) && ...
    isfinite(slotIdx) && slotIdx>=1 && slotIdx==fix(slotIdx) && slotIdx<flintmax, ...
    id,'Use the exact one-based original capture slot.');
timing=sixgr.phy.frame.SSBTimingResolver.resolveFromConfig(cfg);
burst=sixgr.phy.ia.SSBBurstPlan.fromConfig(cfg,timing);
indices=double(burst.ActiveSSBIndices0Based(:).');
assert(isstruct(received) && isscalar(received) && ...
    all(isfield(received,{'CandidateSSBIndices','CandidateResults'})) && ...
    isa(received.CandidateSSBIndices,'double') && isreal(received.CandidateSSBIndices) && ...
    isvector(received.CandidateSSBIndices) && ...
    isequal(received.CandidateSSBIndices(:).',indices) && ...
    iscell(received.CandidateResults) && numel(received.CandidateResults)==numel(indices), ...
    id,'Retain every original configured candidate exactly once and in its original requested order.');
clockNames=["ObservationStartSample","ObservationEndSampleExclusive", ...
    "ObservationSampleRateHz","ObservationCompletionTime_s"];
textNames=["ObservationCoverageSource","ReceiverObservationSHA256", ...
    "ReceiverObservationHashPlane","ReceiverObservationHashSerialization"];
for candidate=[{received},reshape(received.CandidateResults,1,[])]
    row=candidate{1};
    assert(isstruct(row) && isscalar(row) && all(isfield(row,[clockNames,textNames,"RuntimeStageWaveformsUsed"])), ...
        'sixgr:truth:ReceivedSSBBurstClock','Retain original complete receiver clock and sample-hash evidence.');
    for name=clockNames
        value=row.(name);
        assert(isa(value,'double') && isreal(value) && isscalar(value) && isfinite(value) && value>=0, ...
            'sixgr:truth:ReceivedSSBBurstClock','Original sample clocks must be finite double scalars.');
        assert(isequal(value,received.(name)), ...
            'sixgr:truth:ReceivedSSBBurstClock','Every candidate must use the same original capture clock.');
    end
    for name=textNames
        assert(isstring(row.(name)) && isscalar(row.(name)) && ~ismissing(row.(name)) && ...
            strlength(row.(name))>0 && isequal(row.(name),received.(name)), ...
            'sixgr:truth:ReceivedSSBBurstClock','Every candidate must retain the same original input hash/plane.');
    end
    assert(islogical(row.RuntimeStageWaveformsUsed) && isscalar(row.RuntimeStageWaveformsUsed) && ...
        row.RuntimeStageWaveformsUsed,'sixgr:truth:ReceivedSSBBurstClock','Do not promote unbound legacy sample metadata.');
end
carrier=sixgr.phy.grid.makeCarrier(cfg); fs=received.ObservationSampleRateHz;
first=received.ObservationStartSample; stop=received.ObservationEndSampleExclusive;
assert(fs>0 && first==fix(first) && stop==fix(stop) && first<stop && stop<=flintmax && ...
    first==sixgr.phy.frame.slotStartSample(carrier,slotIdx-1,fs) && ...
    received.ObservationCompletionTime_s==stop/fs && ...
    received.ObservationCoverageSource=="complete_contiguous_received_sample_buffer" && ...
    received.ReceiverObservationHashPlane=="actual_receiver_input_before_synchronization" && ...
    received.ReceiverObservationHashSerialization=="WaveformHash.runtimeArray_class_dimensions_real_imag_double" && ...
    ~isempty(regexp(char(received.ReceiverObservationSHA256),'^[0-9A-Fa-f]{64}$','once')), ...
    'sixgr:truth:ReceivedSSBBurstClock','Use the original absolute capture, not candidate-local or configured future samples.');
for k=1:numel(indices)
    row=received.CandidateResults{k};
    assert(isfield(row,'RequestedSSBOccasionIndex') && isa(row.RequestedSSBOccasionIndex,'double') && ...
        isreal(row.RequestedSSBOccasionIndex) && isscalar(row.RequestedSSBOccasionIndex) && ...
        isequal(row.RequestedSSBOccasionIndex,indices(k)),id, ...
        'Each receiver result must preserve its original request identity, even when detection fails.');
end
end
