function evidence=receivedDataSymbolTiming(prepared,observation,timing,availableAtSample)
% Actual received allocation interval, not wall-clock decode latency or N1.
% Availability is the shared owner's result event; the source symbol end
% comes from measured reference alignment and the executed OFDM calendar.
assert(isa(prepared,'sixgr.link.PreparedDataTransmission') && isscalar(prepared), ...
    'sixgr:truth:ReceivedDataTimingPreparationRequired','Retain the actual coded transmission.');
prepared.readObservation(observation, ...
    prepared.RequestBinding.PHYGrant.AntennaArchitecture.NumRxAntennas,'receiver');
required={'AppliedTimingCorrectionSamples','DemodulatedSampleCount', ...
    'TimingSource','OracleTimingUsed','ReceiverZeroPaddingUsed'};
assert(isstruct(timing) && isscalar(timing) && all(isfield(timing,required)) && ...
    ~timing.OracleTimingUsed && ~timing.ReceiverZeroPaddingUsed && ...
    string(timing.TimingSource)=="received_reference_correlation_bounded_search", ...
    'sixgr:truth:MeasuredDataTimingRequired','Use actual received reference timing, never a nominal/channel-truth substitute.');
offset=timing.AppliedTimingCorrectionSamples;
count=timing.DemodulatedSampleCount;
validateattributes(offset,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(count,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(availableAtSample,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
assert(observation.StartSample+offset+count<=observation.EndSampleExclusive && ...
    availableAtSample>=observation.EndSampleExclusive, ...
    'sixgr:truth:DataTimingOutsideReceivedEvent','The receive result cannot precede its complete actual capture.');
carrier=prepared.Tx.Carrier;
if prepared.Direction=="UL", channel=prepared.Tx.PUSCH;
else, channel=prepared.Tx.PDSCH; end
allocation=double(channel.SymbolAllocation);
info=nrOFDMInfo(carrier,'SampleRate',prepared.SampleRateHz,'Windowing',0);
n=double(carrier.SymbolsPerSlot);
slotInSubframe=mod(double(carrier.NSlot),double(carrier.SlotsPerSubframe));
lengths=double(info.SymbolLengths(slotInSubframe*n+(1:n)));
assert(count==sum(lengths),'sixgr:truth:DataTimingDemodulationExtentMismatch', ...
    'The measured receive extraction must cover the executed complete OFDM slot.');
origin=observation.StartSample+offset;
first=origin+sum(lengths(1:allocation(1)));
last=origin+sum(lengths(1:sum(allocation)));
grant=prepared.RequestBinding.Grant;
evidence=struct('ContractVersion',"received_data_symbol_timing/v1", ...
    'Direction',prepared.Direction,'RNTI',double(grant.RNTI), ...
    'GrantContextId',string(prepared.RequestBinding.PHYGrant.GrantContextId), ...
    'DataAbsoluteSlot',double(carrier.NFrame)*double(carrier.SlotsPerFrame)+double(carrier.NSlot), ...
    'SymbolAllocation',allocation,'SampleRateHz',prepared.SampleRateHz, ...
    'ObservationStartSample',observation.StartSample, ...
    'ObservationEndSampleExclusive',observation.EndSampleExclusive, ...
    'AppliedTimingCorrectionSamples',offset,'ReceivedSymbolStartSample',first, ...
    'ReceivedSymbolEndSampleExclusive',last,'ResultAvailableAtSample',double(availableAtSample), ...
    'Source',"actual_received_reference_alignment_and_executed_OFDM_symbol_lengths", ...
    'ProcessingBudgetIncluded',false);
end
