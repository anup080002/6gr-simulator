function [T,diagnosticContext,observation,evidence]=exportSharedScoringWaveformObservation(root,T,planes,prepared,planeID)
% Persist the exact executed desired-link IQ without a full path-gain tensor.
% This is effective-link evidence after TX RF/channel/loss and before
% receiver noise/RX RF.  It is never a practical receiver input.
arguments
    root {mustBeTextScalar}
    T table
    planes struct
    prepared
    planeID {mustBeTextScalar}
end
assert(istable(T) && height(T)==1 && isfolder(root), ...
    'sixgr:truth:ScoringWaveformExportScope', ...
    'One completed trial and an existing run folder are required.');
[observation,evidence]=sixgr.truth.sharedLinkScoringObservation(planes,prepared,planeID);
waveform=observation.readComplete();
assert(~isempty(waveform) && all(isfinite(waveform),'all') && ...
    ~logical(evidence.ReceiverEstimatorInput) && ...
    double(evidence.AdditionalChannelExecutions)==0 && ...
    double(evidence.AdditionalRFExecutions)==0, ...
    'sixgr:truth:InvalidSharedScoringWaveform', ...
    'Persist only the complete same-execution desired-link scoring plane.');
waveformHash=sixgr.channel.ChannelFactory.runtimeNumericArraySHA256(waveform);
identityHash=sixgr.phy.waveform.WaveformHash.bytes(string(evidence.LinkID)+"|"+ ...
    string(observation.StartSample)+"|"+string(observation.EndSampleExclusive)+"|"+waveformHash);
id="effch_"+identityHash;
matRelative=fullfile('channel','mat',id+".mat");
csvRelative=fullfile('channel','csv',id+"_segments.csv");
matPath=fullfile(root,matRelative); csvPath=fullfile(root,csvRelative);
manifest=struct('Contract',"actual_shared_effective_link_waveform/v1", ...
    'Representation',"complete_sample_indexed_desired_link_IQ_not_path_gain_tensor", ...
    'Source',evidence.Source,'Scope',evidence.Scope,'LinkID',evidence.LinkID, ...
    'TransmitterID',evidence.TransmitterID,'ReceiverID',evidence.ReceiverID, ...
    'SampleRateHz',observation.SampleRateHz,'StartSample',observation.StartSample, ...
    'EndSampleExclusive',observation.EndSampleExclusive,'WaveformSHA256',waveformHash, ...
    'ReceiverEstimatorInput',false,'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0);
manifestJSON=string(jsonencode(manifest));
if ~isfile(matPath)
    sixgr.util.matSave(matPath,struct('ManifestJSON',manifestJSON, ...
        'DesiredLinkWaveform',waveform,'Evidence',evidence),'UseArtifactStore',false);
end
row=table(id,evidence.LinkID,evidence.TransmitterID,evidence.ReceiverID, ...
    observation.StartSample,observation.EndSampleExclusive,observation.SampleRateHz, ...
    size(waveform,1),size(waveform,2),waveformHash,string(matRelative), ...
    false,0,0,'VariableNames',{'ChannelObservationID','LinkID','TransmitterID', ...
    'ReceiverID','StartSample','EndSampleExclusive','SampleRateHz','TimeSampleCount', ...
    'ReceiveBranchCount','WaveformSHA256','WaveformMATFile','ReceiverEstimatorInput', ...
    'AdditionalChannelExecutions','AdditionalRFExecutions'});
if ~isfile(csvPath)
    sixgr.util.csvWriteTable(csvPath,row,'PreserveSchema',true);
end
assert(sixgr.phy.waveform.WaveformHash.file(matPath)~="" && ...
    sixgr.phy.waveform.WaveformHash.file(csvPath)~="", ...
    'sixgr:truth:SharedScoringWaveformPublicationFailed', ...
    'The immutable effective-link waveform artifacts must be readable.');
T.ChannelObservationID=id;
T.ChannelObservationManifestJSON=manifestJSON;
T.ChannelObservationManifestSHA256=sixgr.phy.waveform.WaveformHash.bytes(manifestJSON);
T.ChannelObservationMATFile=string(matRelative);
T.ChannelObservationMATFileSHA256=sixgr.phy.waveform.WaveformHash.file(matPath);
T.ChannelObservationSegmentsCSV=string(csvRelative);
T.ChannelObservationSegmentsCSVSHA256=sixgr.phy.waveform.WaveformHash.file(csvPath);
T.ChannelObservationSegmentCount=height(row);
T.ChannelObservationStartSample=observation.StartSample;
T.ChannelObservationEndSampleExclusive=observation.EndSampleExclusive;
T.ChannelObservationSampleRateHz=observation.SampleRateHz;
T.ChannelObservationSource=string(evidence.Source);
T.ChannelObservationReceiverEstimatorInput=false;
T.RuntimeChannelStartSample=observation.StartSample;
T.RuntimeChannelEndSample=observation.EndSampleExclusive;
T.RuntimeChannelCanonicalInputSamples=size(waveform,1);
T.RuntimeChannelCaptureScope="complete_executed_effective_link_waveform_bounded_path_gain_preview_separate";
T.RuntimeChannelPathGainElementCount=0;
T.RuntimeChannelPathGainDimensions="[]";
T.RuntimeChannelPathGainsSHA256="";
diagnosticContext=struct('PostChannelWaveform',waveform, ...
    'PostChannelWaveformSHA256',waveformHash, ...
    'PostChannelWaveformSource','actual_desired_link_after_tx_rf_channel_and_large_scale_loss_before_sum_noise_and_rx_rf', ...
    'RuntimeChannelPathGains',complex([]),'RuntimeChannelPathGainSampleTimes_s',[], ...
    'RuntimeChannelPathDelays_s',[],'RuntimeChannelPathGainsSHA256',"", ...
    'RuntimeChannelStartSample',observation.StartSample, ...
    'RuntimeChannelEndSample',observation.EndSampleExclusive, ...
    'RuntimeChannelCanonicalInputSamples',size(waveform,1), ...
    'RuntimeChannelCaptureScope',T.RuntimeChannelCaptureScope, ...
    'RuntimeChannelObjectClockExact',true,'RuntimeChannelLinkKey',string(evidence.LinkID), ...
    'RuntimeChannelStateKey',"retained_in_segment_execution_evidence", ...
    'RuntimeChannelSeed',NaN,'RuntimeChannelReciprocityExact',false, ...
    'RuntimeChannelReciprocityDirection',"",'RuntimeChannelReciprocitySource',"", ...
    'RuntimeChannelReciprocityApproximationMode',"", ...
    'RuntimeChannelTransmitAndReceiveSwapped',false, ...
    'RuntimeChannelAngleEvidenceAvailable',false,'RuntimeChannelAnglesAoD_deg',[], ...
    'RuntimeChannelAnglesAoA_deg',[],'RuntimeChannelAnglesZoD_deg',[], ...
    'RuntimeChannelAnglesZoA_deg',[],'RuntimeChannelAngleCoordinateFrame',"", ...
    'RuntimeChannelAngleEvidenceSource', ...
    "bounded_channel_model_preview_is_published_by_runtime_replay_not_duplicated_per_trial");
end
