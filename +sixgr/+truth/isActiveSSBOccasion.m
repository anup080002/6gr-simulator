function [tf, occasion] = isActiveSSBOccasion(cfg, slotIdx)
%ISACTIVESSBOCCASION Resolve active SS/PBCH candidates in a runtime slot.
%
% slotIdx is the coupled runtime's one-based absolute carrier-slot index.
% Candidate timing and the active bitmap come from the canonical
% FrameStructureEngine snapshot produced during configuration validation.

occasion = localEmptyOccasion(slotIdx);
tf = false;
if ~(isnumeric(slotIdx) && isscalar(slotIdx) && ...
        isfinite(double(slotIdx)) && double(slotIdx) >= 1 && ...
        double(slotIdx) == fix(double(slotIdx)))
    return;
end
if ~logical(sixgr.util.structGet(cfg, "phy.ssb.enable", false))
    occasion.Source = "ssb_disabled_by_yaml";
    return;
end

periodSlots = double(sixgr.util.structGet( ...
    cfg, "phy.ssb.periodCarrierSlots", NaN));
activeIndices0 = double(sixgr.util.structGet( ...
    cfg, "phy.ssb.activeCandidateIndices0Based", []));
activeSlots0 = double(sixgr.util.structGet( ...
    cfg, "phy.ssb.activeCarrierSlots0Based", []));
if ~(isfinite(periodSlots) && periodSlots >= 1 && ...
        periodSlots == fix(periodSlots) && ...
        numel(activeIndices0) == numel(activeSlots0))
    frameStructure = sixgr.phy.FrameStructureEngine(cfg);
    occasion = frameStructure.SSBOccasion(double(slotIdx) - 1);
    occasion.RuntimeCarrierSlot1Based = double(slotIdx);
    tf = logical(occasion.Active);
    return;
end

canonicalSlot0 = mod(double(slotIdx) - 1, periodSlots);
mask = activeSlots0(:).' == canonicalSlot0;
candidateIndices0 = activeIndices0(mask);
timing = sixgr.util.structGet(cfg, "phy.ssb.timing", struct());
if isempty(fieldnames(timing))
    error("sixgr:truth:MissingCanonicalSSBTiming", ...
        ["The validated SSB carrier-slot aliases exist, but the canonical " ...
         "phy.ssb.timing snapshot is missing."]);
end

occasion.RuntimeCarrierSlot1Based = double(slotIdx);
occasion.AbsoluteCarrierSlot0Based = double(slotIdx) - 1;
occasion.CarrierSlotWithinPeriod0Based = canonicalSlot0;
occasion.PeriodCarrierSlots = periodSlots;
occasion.Active = ~isempty(candidateIndices0);
occasion.ActiveSSBIndices0Based = candidateIndices0(:).';
occasion.Source = "validated_phy.ssb_carrier_slot_aliases";
if ~isempty(candidateIndices0)
    startsWithin = double(timing. ...
        CandidateStartSymbolsWithinHalfFrame(candidateIndices0 + 1));
    absoluteStarts = double(timing. ...
        CandidateStartSymbols(candidateIndices0 + 1));
    occasion.CandidateStartSymbolsWithinHalfFrame0Based = ...
        startsWithin(:).';
    occasion.CandidateAbsoluteStartSymbols0Based = ...
        absoluteStarts(:).';
    occasion.CandidateSSBSymbolsWithinSlot0Based = ...
        mod(absoluteStarts, double(timing.SymbolsPerSlot));
    occasion.CandidateCarrierStartTimesMs = ...
        absoluteStarts ./ (double(timing.SymbolsPerSlot) * ...
        (2 ^ double(timing.Mu)));
end
tf = logical(occasion.Active);
end

function occasion = localEmptyOccasion(slotIdx)
occasion = struct( ...
    "ContractVersion", "sixgr_ssb_carrier_slot_occasion/v1", ...
    "IndexConvention", "zero_based_phy_indices_with_one_based_runtime_alias", ...
    "RuntimeCarrierSlot1Based", double(slotIdx), ...
    "AbsoluteCarrierSlot0Based", NaN, ...
    "CarrierSlotWithinPeriod0Based", NaN, ...
    "PeriodCarrierSlots", NaN, ...
    "Active", false, ...
    "ActiveSSBIndices0Based", zeros(1, 0), ...
    "CandidateStartSymbolsWithinHalfFrame0Based", zeros(1, 0), ...
    "CandidateAbsoluteStartSymbols0Based", zeros(1, 0), ...
    "CandidateSSBSymbolsWithinSlot0Based", zeros(1, 0), ...
    "CandidateCarrierStartTimesMs", zeros(1, 0), ...
    "Source", "not_resolved");
end
