function mapping=buildScheduledHARQACKMapping(state,cfg,ue,targetSlot)
% gNB bit identities from its physically executed DL schedule, never UE ACKs.
validateattributes(ue,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(targetSlot,{'numeric'},{'scalar','real','finite','integer','positive'});
owner=state.SharedWaveformStream;
assert(isa(owner,'sixgr.truth.CoupledWaveformStream'), ...
    'sixgr:truth:HARQMappingPhysicalOwnerRequired','Use the actual shared physical owner.');
context=sixgr.phy.pdcch.DCIContextFactory.fromRuntimeConfig(cfg,'1_1');
assert(context.Data.DAIWidth==2 && ...
    context.Data.ConnectedPolicy.harq_ack_codebook=="dynamic" && ...
    context.Data.DLReferenceSignaling.max_codewords==1, ...
    'sixgr:truth:UnsupportedScheduledHARQMapping','Require ordinary scalar-TB Type-2 feedback.');
expectations=sixgr.truth.scheduledHARQExpectationsForOccasion(state,ue,targetSlot);
transmitted=sixgr.util.structGet(state,'SharedDataTXLedger',{});
actual=owner.DataTransmissions;
records=struct([]); key=zeros(0,2); lastGrants={};
for k=1:numel(expectations)
    e=expectations{k};
    if e.UEIndex~=ue || e.FeedbackAbsoluteSlot0+1~=targetSlot, continue; end
    hit=find(cellfun(@(tx)tx.Identity.TransmissionID==e.TransmissionID,transmitted));
    physical=find(arrayfun(@(tx)tx.Identity.TransmissionID==e.TransmissionID,actual));
    assert(isscalar(hit) && isscalar(physical), ...
        'sixgr:truth:HARQMappingUnexecutedSchedule','An expectation needs its exact actual transmission.');
    tx=transmitted{hit};
    assert(isequaln(tx.Identity,actual(physical).Identity) && ...
        tx.CommittedAtSample==actual(physical).CommittedAtSample && ...
        tx.CommittedAtSample<=owner.Events.NextSampleIndex && ...
        isequaln(e,sixgr.truth.scheduledDLHARQExpectation(tx.Grant,tx.Identity,tx.CommittedAtSample)), ...
        'sixgr:truth:HARQMappingScheduleMismatch','Retained expectation differs from the physically committed grant.');
    packedContext=sixgr.phy.pdcch.DCIContext(e.ScheduledDCI.ContextData);
    assert(packedContext.Digest==context.Digest && e.RNTI==context.Data.RNTIValue, ...
        'sixgr:truth:HARQMappingContextMismatch','The gNB expectation must match this installed context.');
    parsed=sixgr.phy.pdcch.decodeDCIPayload(e.ScheduledDCI.Bits,'1_1',packedContext);
    timing=tx.Grant.TimingDecision;
    row=struct('BitIndex',NaN,'TransmissionID',e.TransmissionID, ...
        'PHYGrantContextId',e.PHYGrantContextId,'UEIndex',e.UEIndex,'RNTI',e.RNTI, ...
        'HARQProcess',e.HARQProcess,'NDI',e.NDI,'SourceSlot',e.DataAbsoluteSlot0+1, ...
        'TargetSlot',targetSlot,'ControlAbsoluteSlot',e.ControlAbsoluteSlot0, ...
        'ControlStartSymbol',double(timing.ControlSymbolAllocation(1)), ...
        'CounterDAIRaw',double(parsed.Fields.dai), ...
        'ScheduledPayloadHash',string(parsed.PayloadHash), ...
        'ConfigurationEpoch',double(context.Data.ConfigurationEpoch));
    if isempty(records), records=row; else, records(end+1)=row; end %#ok<AGROW>
    key(end+1,:)=[row.ControlAbsoluteSlot row.ControlStartSymbol]; %#ok<AGROW>
    lastGrants{end+1}=tx.Grant; %#ok<AGROW>
end
assert(~isempty(records),'sixgr:truth:MissingScheduledHARQMapping', ...
    'A shared HARQ receiver needs a transmitted schedule for this occasion.');
[key,order]=sortrows(key,[1 2]); records=records(order); lastGrants=lastGrants(order);
assert(size(unique(key,'rows'),1)==numel(records) && ...
    numel(unique(string({records.TransmissionID})))==numel(records), ...
    'sixgr:truth:DuplicateScheduledHARQMapping','One transmitted scalar-TB assignment per monitoring pair is supported.');
for k=1:numel(records)
    assert(records(k).CounterDAIRaw==mod(k-1,4), ...
        'sixgr:truth:ScheduledHARQCounterMismatch', ...
        'Transmitted DAI must match the independent complete gNB occasion count.');
    records(k).BitIndex=k;
end
mapping=struct('Records',records,'BitCount',numel(records),'UEIndex',ue, ...
    'RNTI',double(context.Data.RNTIValue),'TargetSlot',targetSlot, ...
    'ConfigurationEpoch',double(context.Data.ConfigurationEpoch), ...
    'ContextDigest',context.Digest,'LastGrant',lastGrants{end}, ...
    'Source',"physically_transmitted_dl_schedule_not_ue_feedback_state");
% Hash the bit mapping, not the complex-valued PHY grant object. Every row
% already binds its physical grant identity and exact scheduled DCI hash;
% the retained original grant is separate input for later resource planning.
mapping.Digest=sixgr.phy.pucch.PUCCHUtil.hash(rmfield(mapping,'LastGrant'));
end
