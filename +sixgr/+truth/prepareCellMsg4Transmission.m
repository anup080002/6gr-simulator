% Requires actual independent cell Msg3 completion.
function prepared=prepareCellMsg4Transmission(cfg,ra,msg4,proposal,received)
% Prepare a cell-owned common Msg4; only the shared owner executes TX RF.
assert(ra.ContextSHA256==localHash(rmfield(ra,'ContextSHA256')) && ...
    proposal.SHA256==localHash(rmfield(proposal,'SHA256')) && ...
    proposal.ResponseSchedulable && ra.CellMsg4ProposalSHA256==proposal.SHA256 && ...
    proposal.OriginalReceiveReceiptSHA256==received.SHA256 && ...
    received.SHA256==localHash(rmfield(received,'SHA256')) && ...
    received.CRCPass && received.SemanticAccepted && ...
    msg4.EncodingProfile=="nr_rrc_access_base_srb1_uper_v1" && ...
    isequal(msg4.ContentionIdentityBytes,received.Message.ContentionIdentityBytes), ...
    'sixgr:truth:CellMsg4PreparationContract','Retain the original accepted cell Msg3 and exact response proposal.');
[tx,schedule]=sixgr.phy.ra.generateMsg4Waveform(cfg,ra,msg4);
assert(size(tx.Waveform,2)==1,'sixgr:truth:CellMsg4LogicalPortMismatch','Common Msg4 has one logical layer/port before its SSB mapping.');
info=nrOFDMInfo(tx.Carrier); fs=info.SampleRate;
first=sixgr.phy.frame.slotStartSample(tx.Carrier,ra.Msg4Slot,fs);
assert(first>=received.ObservationEndSampleExclusive,'sixgr:truth:CellMsg4CausalPreparation','Do not enqueue Msg4 before its actual received Msg3.');
cfg.lls6g.userContext.RuntimeSignalFamily="Msg4";
cfg.lls6g.userContext.RuntimeCurrentDirection="DL";
cfg.lls6g.userContext.Direction="DL";
cfg.lls6g.userContext.RuntimeServingCell=ra.ServingCell;
cfg.lls6g.userContext.RuntimeServingCellIndex=ra.ServingCell;
source="lls6g.resolvedConfig.power_and_rf_frontend.bs_tx_power_dbm";
power=sixgr.util.structGet(cfg,source,NaN);
if sixgr.rf.isNormalizedFixedSNRPowerReference(cfg)
    power=0; source="normalized_fixed_esn0_unit_occupied_re_es";
else
    validateattributes(power,{'numeric'},{'scalar','real','finite'});
end
ctx=sixgr.rf.PowerContext(cfg,'DL','NumPorts',1);
ctx.TotalTxPower_dBm=power; ctx.TotalTxPower_mW=10^(power/10);
ctx.TotalTxPower_W=ctx.TotalTxPower_mW*1e-3; ctx.TotalTxPowerSource=char(source);
ctx.SignalSpecificPowerControl=true; ctx.SignalFamily='Msg4';
txInfo=struct('OFDM',info,'PortGrid',tx.Grid, ...
    'PowerNormalizationGridSource',"exact_cell_Msg4_composite_pdcch_pdsch_grid");
[wave,ctx]=sixgr.rf.applyPowerContext(tx.Waveform,cfg,'DL',txInfo,'PowerContext',ctx,'ApplyPA',false);
selected=sixgr.phy.ia.SSBBurstPlan.selectedPrecoderFromConfig(cfg,ra.AssociatedSSBIndex0);
[matrix,beam,association]=sixgr.phy.ra.resolveAssociatedSSBProjection(cfg,selected.NumTransmitAntennas);
physical=wave*cast(matrix,'like',wave).';
% No UE checkpoint or future configured SetupComplete allocation is used.
reservations=sixgr.truth.CommonRAResourceCalendar.fromTransmission(tx,ra,"Msg4");
tx.PowerControl=struct('Msg4TxPower_dBm',power,'DownlinkTxPowerSource',source, ...
    'Scope',"configured_cell_power_budget_before_shared_TX_RF");
unit=sixgr.rf.appliedWaveformAmplitudeUnit(cfg,ctx);
prepared=struct('ContractVersion',"prepared_cell_Msg4/v1",'StageName',"Msg4",'Direction',"DL", ...
    'AbsoluteSlot',ra.Msg4Slot,'ServingCell',ra.ServingCell,'TemporaryCRNTI',ra.TempCRNTI, ...
    'Waveform',tx.Waveform,'PhysicalWaveform',physical, ...
    'SampleRate_Hz',fs,'SampleCount',size(physical,1),'PortCount',1, ...
    'PhysicalPortCount',size(physical,2),'Duration_s',size(physical,1)/fs, ...
    'StartTime_s',first/fs,'EndTimeExclusive_s',(first+size(physical,1))/fs, ...
    'TransmitStartSample',first,'TimeReference',"absolute_cell_sample_clock", ...
    'ExecutionStatus',"generated_not_propagated",'RFExecutionDeferred',true, ...
    'PowerContext',ctx,'CommonResourceReservations',reservations, ...
    'TransmitMappingSource',"original_cell_RO_partition_SSB_retained_from_received_Msg3_grant", ...
    'TransmitBeamID',beam,'TransmitProjectionMatrix',matrix, ...
    'TransmitProjectionMatrixSHA256',string(sixgr.phy.mimo.MatrixContract.digest(matrix)), ...
    'TxSSBAssociationJSON',string(jsonencode(association)), ...
    'PhysicalWaveformPlane',"physical_antenna_"+unit+"_before_shared_tx_rf", ...
    'ReceiverReceiptSHA256',received.SHA256,'CellCalendarSHA256',ra.CellCalendarSHA256, ...
    'ResponseProposal',proposal,'OriginalMsg3ReceiveReceipt',received,'RAContext',ra,'Tx',tx,'Schedule',schedule,'Config',cfg);
end
function h=localHash(value)
h=string(sixgr.util.sha256Hex(jsonencode(sixgr.util.jsonSafeValue(value))));
end
