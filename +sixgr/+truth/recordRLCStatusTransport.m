function state=recordRLCStatusTransport(state,binding,identity,stage,sample,crc,status)
% Actual owner callbacks only; separate control transport from application credit.
assert(binding.ControlOnly&&binding.ApplicationPayloadBytes==0&&binding.Direction==identity.Direction, ...
    'sixgr:protocol:ReverseStatusOwner','Original control-only binding and direction required.');
row=table(string(binding.TBID),string(identity.TransmissionID),double(identity.UEIndex), ...
    double(identity.RNTI),string(binding.BearerID),string(binding.Direction),string(binding.DataDirection), ...
    double(binding.ConfigurationEpoch),string(stage),double(sample),double(identity.SampleRateHz), ...
    double(crc),string(status),string(binding.MACSHA256),string(binding.EncodedSHA256),0, ...
    'VariableNames',{'TransportBlockID','TransmissionID','UEIndex','RNTI','BearerID','Direction', ...
    'AcknowledgedDataDirection','ConfigurationEpoch','Stage','Sample','SampleRateHz','CRCPass', ...
    'Status','MACSHA256','RLCStatusSHA256','ApplicationCreditedBits'});
state.RLCStatusTransportLedgerTable=[sixgr.util.structGet(state,'RLCStatusTransportLedgerTable',table());row];
end
