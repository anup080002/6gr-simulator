function T=collectReceivedPUCCHPowerHistory(state)
% Only original physically committed ledger entries become primary rows.
% A prepared proposal, received command or withheld occasion produces no row.
T=table();
ledger=sixgr.util.structGet(state,'SharedPUCCHTXLedger',{});
owners=sixgr.util.structGet(state,'SharedReceivedPUCCHPowerOwners',{});
seen=strings(0,1);
for k=1:numel(ledger)
    entry=ledger{k};
    if ~isfield(entry,'ReceivedPowerHistory'), continue; end
    id='sixgr:truth:PUCCHPowerHistoryBinding'; h=entry.ReceivedPowerHistory; x=entry.Identity;
    assert(entry.Source=="actual_shared_PUCCH_transmission_started_not_receiver_outcome" && ...
        x.TransmissionID==h.TransmissionID && x.AssignmentDigest==h.TransmissionAssignmentDigest && ...
        x.ObservationID==h.Occasion.ObservationID && x.UEIndex==h.Occasion.UEID && ...
        x.RNTI==h.Occasion.RNTI && x.RFConfigurationEpoch==h.Occasion.ClockEpoch && ...
        x.SampleRateHz==h.Occasion.SampleRateHz && ...
        entry.CommittedAtSample==entry.FirstActiveSample+1 && h.CommittedAtSample==entry.CommittedAtSample && ...
        entry.FirstActiveSample>=h.Occasion.StartSample && entry.FirstActiveSample<h.Occasion.EndSampleExclusive, ...
        id,'Retain the original committed transmission identity, interval and history.');
    assert(~any(seen==x.TransmissionID),id,'A committed original transmission must be published once.');
    assert(numel(owners)>=x.UEIndex && isa(owners{x.UEIndex},'sixgr.link.ReceivedPUCCHPowerControlState') && ...
        nnz(cellfun(@(original)isequaln(original,h),owners{x.UEIndex}.History))==1, ...
        id,'Do not manufacture a history from a receiver result or standalone proposal.');
    digest=string(sixgr.rrc.asn1.asn1SHA256Hex(uint8(unicode2native( ...
        jsonencode(orderfields(rmfield(h,'Digest'))),'UTF-8'))));
    assert(digest==h.Digest && h.Power.ClosedLoopAdjustment_dB==h.UpdatedG_dB && ...
        h.Power.AppliedPower_dBm==min(h.Power.PCMAX_dBm,max(h.Power.MinimumPower_dBm,h.Power.RequestedPower_dBm)), ...
        id,'Retain original power arithmetic and signed history operands.');
    seen(end+1,1)=x.TransmissionID; %#ok<AGROW>
    row=struct('UEIndex',x.UEIndex,'RNTI',x.RNTI,'ServingCell',h.Occasion.ServingCell, ...
        'ComponentCarrier',h.Occasion.ComponentCarrier,'ActiveULBWP',h.Occasion.ActiveULBWP, ...
        'Slot',floor(h.Occasion.StartSymbolBoundary/14)+1,'ObservationID',string(x.ObservationID), ...
        'TransmissionID',string(x.TransmissionID),'AssignmentSHA256',string(x.AssignmentDigest), ...
        'InstallationID',h.InstallationID,'InstallationSHA256',h.InstallationDigest, ...
        'ProposalSHA256',h.Power.PowerProposalDigest,'HistorySHA256',h.Digest, ...
        'HistoryJSON',string(jsonencode(h)),'FirstActiveSample',entry.FirstActiveSample, ...
        'CommittedAtSample',entry.CommittedAtSample,'ClockEpoch',h.Occasion.ClockEpoch, ...
        'SampleRateHz',h.Occasion.SampleRateHz,'PreviousG_dB',h.PreviousG_dB, ...
        'NetTPC_dB',h.NetTPC_dB,'UpdatedG_dB',h.UpdatedG_dB, ...
        'P0_dBm',h.Power.P0_dBm,'RequestedPower_dBm',h.Power.RequestedPower_dBm, ...
        'AppliedPower_dBm',h.Power.AppliedPower_dBm,'PCMAX_dBm',h.Power.PCMAX_dBm, ...
        'AtMaximumPower',h.AtMaximumPower,'AtMinimumPower',h.AtMinimumPower, ...
        'CutoffSymbolBoundary',h.CutoffSymbolBoundary,'KPUCCHSymbols',h.KPUCCHSymbols, ...
        'AppliedAssignmentDigestsJSON',string(jsonencode(h.AppliedOrHeldAssignmentDigests)), ...
        'DeferredAssignmentDigestsJSON',string(jsonencode(h.DeferredAssignmentDigests)), ...
        'PowerOwnerCommitted',true,'ReferencePlane',"pre_node_RF_original_PUCCH_contribution_target", ...
        'Source',"original_shared_PUCCH_first_active_sample_commit");
    T=[T;struct2table(row,'AsArray',true)]; %#ok<AGROW>
end
end
