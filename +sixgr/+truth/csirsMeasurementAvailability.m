function [availableSlot,usable,clocked]=csirsMeasurementAvailability(row,requireClock)
% Validate publication chronology; actual sample binding belongs to the RX owner.
flags=["Transmitted","Observed","Consumed","ResourceExtractionAvailable", ...
    "ChannelEstimateAvailable","CSIMeasurementAvailable"];
for name=flags
    assert(ismember(name,string(row.Properties.VariableNames)), ...
        'sixgr:truth:CSIRSProducerSchemaIncomplete','Missing CSI receiver flag %s.',name);
    value=row.(name);
    assert((isnumeric(value)||islogical(value)) && isscalar(value) && isreal(value) && ...
        isfinite(double(value)) && (value==0||value==1), ...
        'sixgr:truth:InvalidCSIRSProducerFlag','CSI receiver flags must be explicit binary scalars.');
end
usable=all(table2array(row(:,cellstr(flags)))==1);
sourceSlot=row.Slot;
validateattributes(sourceSlot,{'numeric'},{'scalar','real','finite','integer','positive'});
availableSlot=sourceSlot;
if ismember('ObservationDeliverySlot',row.Properties.VariableNames)
    availableSlot=row.ObservationDeliverySlot;
    validateattributes(availableSlot,{'numeric'},{'scalar','real','finite','integer','>=',sourceSlot});
end
domain="";
if ismember('MeasurementClockDomain',row.Properties.VariableNames)
    domain=string(row.MeasurementClockDomain);
    assert(isscalar(domain) && ~ismissing(domain) && ...
        any(domain==["slot_only","shared_receiver_sample_clock/v1"]), ...
        'sixgr:truth:InvalidCSIRSReceiverClock','Unknown CSI measurement clock domain.');
end
clocked=domain=="shared_receiver_sample_clock/v1";
if ~clocked
    for field=["ResultAvailableAtSample","MeasurementClockEpoch"]
        if ismember(field,row.Properties.VariableNames)
            value=row.(field);
            assert(isnumeric(value) && isscalar(value) && isreal(value) && isnan(value), ...
                'sixgr:truth:InvalidCSIRSReceiverClock', ...
                'Sample availability/epoch cannot be discarded by a missing or slot-only domain.');
        end
    end
end
assert(~requireClock || clocked,'sixgr:truth:MissingCSIRSReceiverClock', ...
    'Shared CSI publication requires the actual completed receiver sample clock.');
if ~clocked, return; end
names=["ObservationStartSample","ObservationEndSampleExclusive", ...
    "ObservationSampleRateHz","ResultAvailableAtSample","MeasurementClockEpoch", ...
    "DeliverySlotStartSample","DeliverySlotEndSampleExclusive","ObservationDeliverySlot"];
assert(all(ismember(names,string(row.Properties.VariableNames))), ...
    'sixgr:truth:InvalidCSIRSReceiverClock','Incomplete CSI receiver clock.');
for name=names
    value=row.(name);
    assert(isnumeric(value) && isreal(value) && isscalar(value) && isfinite(value) && ...
        value>=0 && value<=flintmax && (name=="ObservationSampleRateHz" || value==fix(value)), ...
        'sixgr:truth:InvalidCSIRSReceiverClock','Invalid CSI receiver clock field %s.',name);
end
assert(row.ObservationSampleRateHz>0 && ...
    row.ObservationEndSampleExclusive>row.ObservationStartSample && ...
    row.ResultAvailableAtSample>=row.ObservationEndSampleExclusive && ...
    row.ResultAvailableAtSample>=row.DeliverySlotStartSample && ...
    row.ResultAvailableAtSample<row.DeliverySlotEndSampleExclusive, ...
    'sixgr:truth:InvalidCSIRSReceiverClock','CSI cannot be published before capture completion or outside its delivery slot.');
end
