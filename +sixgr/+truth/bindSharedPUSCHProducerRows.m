function binding=bindSharedPUSCHProducerRows(grant,pending,trace,timeline,mapping,transmissionSlot,deliverySlot)
% Join existing UE bookkeeping to an already validated independent gNB map.
% TX positions score UE events only. They never index the gNB receive vector:
% after a wholly missed DAI cycle the two positions can differ by four.
required={'UCIOnPUSCHFeedbackGrantIds','UCIOnPUSCHFeedbackSourceSlots', ...
    'UCIOnPUSCHFeedbackHARQIds','UCIOnPUSCHFeedbackBitIndices', ...
    'ExpectedUCIBits','PHYGrant','UEIndex','RNTI'};
assert(isstruct(grant) && isscalar(grant) && all(isfield(grant,required)), ...
    'sixgr:truth:MissingSharedPUSCHProducerBinding','Retain exact producer identities and separate transmitted positions.');
token=string(grant.UCIOnPUSCHFeedbackGrantIds);
assert(isscalar(token) && ~ismissing(token),'sixgr:truth:InvalidSharedPUSCHProducerBinding', ...
    'Use a scalar producer identity token.');
ids=split(token,'|'); ids=ids(strlength(ids)>0);
positions=grant.UCIOnPUSCHFeedbackBitIndices;
expected=grant.ExpectedUCIBits;
assert(isnumeric(positions) && isreal(positions) && (isvector(positions)||isempty(positions)) && ...
    all(isfinite(positions(:))) && all(positions(:)==fix(positions(:))) && ...
    all(positions(:)>=1) && all(positions(:)<=numel(expected)) && ...
    numel(unique(positions))==numel(positions) && numel(positions)==numel(ids) && ...
    numel(grant.UCIOnPUSCHFeedbackSourceSlots)==numel(ids) && ...
    numel(grant.UCIOnPUSCHFeedbackHARQIds)==numel(ids), ...
    'sixgr:truth:InvalidSharedPUSCHProducerBinding', ...
    'Every real producer needs one unique TX position; protocol gaps have none.');
assert((isnumeric(expected)||islogical(expected)) && isreal(expected) && ...
    (isvector(expected)||isempty(expected)) && all(isfinite(expected(:))) && ...
    all(expected(:)==0|expected(:)==1), ...
    'sixgr:truth:InvalidPUSCHHARQACKEvidence','Validate TX scoring bits without using them as receiver authority.');
binding=struct('Rows',struct([]),'TransmittedBitIndices',double(positions(:)), ...
    'ScheduledBitIndices',zeros(0,1));
if isempty(ids), return; end
assert(isstruct(mapping) && isscalar(mapping) && isfield(mapping,'BaseMapping'), ...
    'sixgr:truth:MissingSharedPUSCHScheduledMapping', ...
    'Real producer rows must join the independent physical DL schedule.');
contract=struct('GrantIDs',ids,'SourceSlots',grant.UCIOnPUSCHFeedbackSourceSlots, ...
    'HARQIDs',grant.UCIOnPUSCHFeedbackHARQIds,'ExpectedBits',expected(positions), ...
    'TransmissionSlot',transmissionSlot,'DeliverySlot',deliverySlot, ...
    'GrantContextID',string(grant.PHYGrant.GrantContextId), ...
    'UEIndex',grant.UEIndex,'RNTI',grant.RNTI);
rows=sixgr.truth.preparePUSCHHARQACKBindings(pending,trace,timeline,contract);
producers=pending([rows.PendingIndex],:);
producers.ScheduledAbsoluteSlot=producers.DueSlot;
indices=sixgr.truth.bindScheduledPUCCHFeedbackRows(mapping.BaseMapping,producers);
binding.Rows=rows;
binding.ScheduledBitIndices=indices;
end
