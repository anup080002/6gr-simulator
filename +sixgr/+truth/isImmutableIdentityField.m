function tf = isImmutableIdentityField(fieldName)
%ISIMMUTABLEIDENTITYFIELD True for provenance fields that cannot be filled.

name = regexprep(lower(char(string(fieldName))), "[^a-z0-9]", "");
exact = ["runid", "runuuid", "runtag", "scenarioid", "confighash", ...
    "configsha256", "resolvedconfigsha256", "executionid", ...
    "finalizationid", "attemptid", "artifactid", "detectedpreambleset", ...
    "sourceartifactid", "sourceartifactsha256", "sourcecsvsha256", ...
    "sourcesha256", "gitcommit", "gitdiffsha256"];
% Message/decoder and frozen-context identities are just as immutable as
% run/artifact identities. In particular, an absent decoded payload after
% CRC failure must not turn into a nonempty display token in a CSV.
tf = any(name == exact) || ...
    ~isempty(regexp(name, '(sha256|hash|digest)(tx|rx)?$', 'once'));
end
