function tf = isImmutableIdentityField(fieldName)
%ISIMMUTABLEIDENTITYFIELD True for provenance fields that cannot be filled.

name = regexprep(lower(char(string(fieldName))), "[^a-z0-9]", "");
exact = ["runid", "runuuid", "runtag", "scenarioid", "confighash", ...
    "configsha256", "resolvedconfigsha256", "executionid", ...
    "finalizationid", "attemptid", "artifactid", "detectedpreambleset", ...
    "sourceartifactid", "sourceartifactsha256", "sourcecsvsha256", ...
    "sourcesha256", "gitcommit", "gitdiffsha256", ...
    "srsconfigurationcontextid", "srsconfigurationcontextversion", "srscurrentinstallationjson", ...
    "controlevmsamplesmatfile", "controlevmsamplesstoragecontract", ...
    "ucionpuschapplied", "ucionpuschsource", "ucionpuschevidencesource", ...
    "ucionpuschflag", "ucionpuschflagdefinition", "ucionpuschflagsource", "ucionpuschflagstatus", ...
    "inputucionpuschflag", "inputucionpuschflagdefinition", "inputucionpuschflagsource", "inputucionpuschflagstatus", ...
    "runtimeevidencesource", "runtimematerializationstatus"];
% These exact UCI/returned-runtime fields also carry owner authority. A
% missing source or plane cannot be filled from a finite reservation flag.
% An absent artifact binding is producer-owned evidence too. Schema union
% legitimately adds empty bindings to historical rows. Decorating them as
% display categories invents a file authority and breaks strict readers.
% Message/decoder and frozen-context identities are just as immutable as
% run/artifact identities. In particular, an absent decoded payload after
% CRC failure must not turn into a nonempty display token in a CSV.
tf = any(name == exact) || ...
    startsWith(name,"acceptedsrs") || startsWith(name,"rawsrs") || ...
    ~isempty(regexp(name, '(sha256|hash|digest)(tx|rx)?$', 'once'));
end
