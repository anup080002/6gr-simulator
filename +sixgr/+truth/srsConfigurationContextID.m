function [id,context]=srsConfigurationContextID(cfg,epoch,ue,servingCell)
% Installed accepted-estimator context, not phase history or an SRI value.
% Phase continuity alone cannot distinguish renamed RRC resources. Retain
% the configured resource list/identity and carrier/BWP context separately.
validateattributes(epoch,{'numeric'},{'real','scalar','finite','integer','nonnegative'});
strict=sixgr.phy.srs.buildSRSConfigFromScenario(cfg);
context=struct('Version',"srs_configuration_context/v1", ...
    'PilotSpatialContextID',sixgr.truth.srsPilotPhaseContextID(cfg,epoch,ue,servingCell), ...
    'ResourceId',strict.ResourceId,'ResourceIds',double(strict.ResourceIds(:).'), ...
    'ResourceSetId',strict.ResourceSetId,'ResourceSetUsage',string(strict.ResourceSetUsage), ...
    'CarrierFrequencyHz',strict.CarrierFrequencyHz,'DuplexMode',string(strict.DuplexMode), ...
    'ULCarrierType',string(strict.ULCarrierType),'BWPId',strict.BWPId, ...
    'BWPStart',strict.BWPStart,'BWPSize',strict.BWPSize);
id=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(context),'UTF-8'))));
end
