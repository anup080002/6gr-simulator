function row=bindSharedCSISelectionQuality(root,row,prepared,reception,csi,planes,reference,receiverWindowID)
% Post-reception private UE-selection audit. No feedback/scheduler mutation.
% Nominal channel, raw-grid equal-power and noise-only objective is a declared
% engineering comparison on the selected resource's pilot union, not a CQI
% conformance test or the objective used by the practical receiver's search.
arguments
    root {mustBeTextScalar}
    row table
    prepared (1,1) struct
    reception (1,1) struct
    csi (1,1) struct
    planes struct
    reference (1,1) struct
    receiverWindowID (1,1) string
end
policy=prepared.ReceiverConfig.measurements.csiSelectionQuality;
assert(policy.Enabled && policy.Support=="selected_resource_pilot_union" && height(row)==1, ...
    'sixgr:truth:CSISelectionBindingPolicy','Bind only explicitly enabled, supported selection studies.');
assert(~ismissing(receiverWindowID) && strlength(strtrim(receiverWindowID))>0 && ...
    ismember('ReceiverWindowID',row.Properties.VariableNames) && ...
    isequal(string(row.ReceiverWindowID),receiverWindowID), ...
    'sixgr:truth:CSISelectionBindingWindowIdentity', ...
    'The canonical receiver row must identify the actual completed parent window; never overwrite a conflicting ID.');
measurement=reception.CSIMeasurementState;
assert(isa(measurement,'sixgr.phy.mimo.CSIMeasurementState') && ...
    measurement.UEID=="UE-"+string(row.UEIndex) && ...
    reference.ReceiverID=="ue_"+string(row.UEIndex)+"_rx" && ...
    reference.TransmitterID=="gnb_"+string(row.CellID) && ...
    string(csi.MeasurementID)==measurement.MeasurementID && ...
    string(csi.CSIMeasurementDigest)==measurement.Digest && ...
    string(csi.MeasurementResourceID)==measurement.ResourceID && ...
    csi.MeasurementSlot==measurement.Slot && csi.CRI==measurement.ResourceOrdinal && ...
    reference.ResourceOrdinal0==measurement.ResourceOrdinal && ...
    "CSI-RS-"+string(reference.ResourceID)==measurement.ResourceID && ...
    reference.SupportScope==policy.Support, ...
    'sixgr:truth:CSISelectionBindingMeasurement', ...
    'Reference and frozen UE recommendation must identify the actual immutable CSI measurement.');
installed=prepared.ReceiverConfig.phy.csi.reportConfiguration;
assert(isstruct(installed) && isscalar(installed) && ...
    installed.Epoch==csi.CSIConfigurationEpoch && ...
    string(installed.ReportConfigID)==string(csi.CSIReportConfigID) && ...
    isequal(double(installed.AllowedRanks),double(csi.RankDomain)), ...
    'sixgr:truth:CSISelectionBindingSearchDomain', ...
    ['This audit requires the installed AllowedRanks and actual search RankDomain to match; ' ...
     'never silently narrow an installed domain or claim unsupported search-domain coverage.']);
request=installed;
if isfield(request,'RankDomain')
    assert(isequal(double(request.RankDomain),double(csi.RankDomain)), ...
        'sixgr:truth:CSISelectionBindingSearchDomain','Installed and executed rank domains differ.');
end
request.RankDomain=double(csi.RankDomain);
reference.InstalledReportRequest=installed;
reference.InstalledReportRequestSHA256=sixgr.util.sha256Hex(jsonencode(orderfields(installed)));
reference.EnumerationRequestDerivation="installed_request_plus_exact_executed_rank_domain_no_restriction_change";

% Associate the original received input with the actual corrected FFT input.
% The physical runtime owns the sample epoch; the report epoch is separate.
sync=reception.ReceiverSynchronizationEvidence;
ofdm=reception.ReceiverOFDMInfo;
assert(sync.Source=="actual_CSI_RS_receiver_input_and_post_synchronization_FFT_input" && ...
    string(sync.InputSHA256)==string(row.ReceiverObservationSHA256) && ...
    string(sync.AlignedSHA256)==string(ofdm.WaveformSHA256) && ...
    sync.InputSampleCount==row.ObservationEndSampleExclusive-row.ObservationStartSample && ...
    sync.NumReceiveAntennas==size(reference.H,1) && ~sync.ZeroPaddingUsed && ...
    sync.AppliedTimingCorrectionSamples==reception.ReceiveTiming.AppliedTimingCorrectionSamples && ...
    sync.CFOCorrectionApplied==reception.ReceiverTrackingCorrection.CFOCorrectionApplied && ...
    isequaln(sync.CFOCorrectionApplied_Hz,reception.ReceiverTrackingCorrection.CFOCorrectionApplied_Hz), ...
    'sixgr:truth:CSISelectionBindingFFTInput','The reference must use the actual received/synchronized FFT-input chain.');
first=row.ObservationStartSample+sync.AppliedTimingCorrectionSamples;
last=first+sync.AlignedSampleCount;
assert(first>=row.ObservationStartSample && last<=row.ObservationEndSampleExclusive && ...
    all(reference.FFTStartSample>=first) && all(reference.FFTEndSampleExclusive<=last) && ...
    all(reference.FFTEndSampleExclusive-reference.FFTStartSample==ofdm.Nfft) && ...
    isequal(unique(reference.Support(:,2)),reference.FFTSymbolIndex0), ...
    'sixgr:truth:CSISelectionBindingFFTSupport','Every scored simultaneous matrix needs an actually observed FFT window.');
reference.ReceiverSynchronizationEvidence=sync;
reference.ReceiverFFTSampleRateHz=ofdm.SampleRate;
reference.ReceiverFFTSize=ofdm.Nfft;
reference.ReceiverCyclicPrefixFraction=ofdm.CyclicPrefixFraction;
row.ReceiverID=string(reference.ReceiverID);
row.ReceiverClockDomain=string(row.MeasurementClockDomain);
row.ReceiverClockEpoch=double(row.MeasurementClockEpoch);
if ismember('RunFolder',row.Properties.VariableNames) && strlength(row.RunFolder)>0
    assert(string(row.RunFolder)==string(root), ...
        'sixgr:truth:CSISelectionBindingPopulation','Archive root must match the queued run identity.');
else
    row.RunFolder=string(root);
end
row.MeasurementUEID=measurement.UEID;
row.TransmitterID=reference.TransmitterID;
row.LinkID=reference.LinkID;
id=struct('MeasurementUEID',row.MeasurementUEID,'UEIndex',row.UEIndex,'CellID',row.CellID,'RNTI',row.RNTI, ...
    'LinkID',row.LinkID,'TransmitterID',row.TransmitterID, ...
    'ReceiverID',row.ReceiverID,'ReceiverWindowID',receiverWindowID, ...
    'ReceiverClockDomain',row.ReceiverClockDomain, ...
    'ReceiverClockEpoch',row.ReceiverClockEpoch, ...
    'ConfigurationEpoch',double(csi.CSIConfigurationEpoch), ...
    'ReportConfigID',string(csi.CSIReportConfigID), ...
    'RequestSHA256',sixgr.util.sha256Hex(jsonencode(orderfields(request))), ...
    'MeasurementID',measurement.MeasurementID,'MeasurementDigest',measurement.Digest, ...
    'ResourceID',measurement.ResourceID,'ResourceOrdinal0',measurement.ResourceOrdinal, ...
    'MeasurementSlot',measurement.Slot,'ObservationStartSample',row.ObservationStartSample, ...
    'ObservationEndSampleExclusive',row.ObservationEndSampleExclusive, ...
    'SampleRateHz',row.ObservationSampleRateHz,'ObservationSHA256',row.ReceiverObservationSHA256);
for name=["RunID","RunTag","RunFolder","ExecutionID","ConfigHash","ScenarioID", ...
        "Seed","RandomSeed","ChannelSeed","NoiseSeed","SweepPointIndex","ConfiguredSNR_dB", ...
        "CSIObservationPopulationSHA256"]
    if ~ismember(name,string(row.Properties.VariableNames)), continue; end
    value=row.(name);
    if (isstring(value)||ischar(value)) && (ismissing(string(value))||strlength(string(value))==0), continue; end
    if isnumeric(value) && isscalar(value) && isnan(value), continue; end
    id.(name)=value;
end
% Keep the original serialized capsule: JSON round trips can change missing
% numeric values. Hash the original text boundary, not a decoded substitute.
if ismember('CSIObservationPopulationSHA256',row.Properties.VariableNames) && ...
        strlength(row.CSIObservationPopulationSHA256)>0
    reference.CSIObservationPopulationJSON=row.CSIObservationPopulationJSON;
    reference.CSIObservationPopulationBindingJSON=row.CSIObservationPopulationBindingJSON;
    reference.CSIObservationPopulationJSONSHA256= ...
        sixgr.util.sha256Hex(char(row.CSIObservationPopulationJSON));
end
id.ObservationID="csi_selection_"+sixgr.util.sha256Hex(jsonencode(orderfields(id)));
reference.Identity=id;
% Copy only actual frozen numeric/text report fields, not live configuration
% objects, private truth operands, or a replacement receiver recommendation.
selection=struct('Identity',id);
fields=["RI","PMI", ...
        "Precoder_W","PrecoderMatrixSHA256","CRI","RankDomain", ...
        "MeasurementID","MeasurementResourceID","MeasurementSlot"];
if request.Ports>2
    fields=[fields,"PMI_I11","PMI_I12","PMI_I13","PMI_I2"];
end
for name=fields
    assert(isfield(csi,name),'sixgr:truth:CSISelectionBindingReport','Actual CSI lacks %s.',name);
    selection.(name)=csi.(name);
end
disturbance=sixgr.truth.captureCSISelectionNoiseEvidence(planes,ofdm,id,size(reference.H,1),receiverWindowID);
policy.PhysicalPowerReferencePlane="raw_native_grid_physical_chain_coefficient_power";
policy.PhysicalPowerUnit="normalized_grid_coefficient_squared_units";
if disturbance.WaveformAmplitudeUnit=="sqrt_mW"
    policy.PhysicalPowerUnit="mW_scaled_grid_coefficient_squared_units";
end
row.CSISelectionQualityIdentityJSON=string(jsonencode(id));
row.CSISelectionQualityObservationID=id.ObservationID;
row=sixgr.truth.exportCSISelectionQuality(root,row,reference,selection,request,disturbance,policy);
end
