function binding=scheduledPDCCHGrantBinding(prepared,context,ue)
% Queue-time identity only. A prepared command is not proof of transmission.
binding=struct();
if ~isfield(context,'Grant'), return; end % Explicit codec/broadcast component.
g=context.Grant;
assert(isstruct(g) && isscalar(g) && all(isfield(g,{'Direction','DCI','PHYGrant','UEIndex','RNTI'})), ...
    'sixgr:truth:InvalidScheduledPDCCHGrant','A scheduled command requires its complete frozen grant.');
direction=upper(string(g.Direction));
sixgr.phy.grant.assertGrantTimingIdentity(g,direction);
sixgr.phy.grant.assertPHYGrantDimensions(g.PHYGrant,'scheduled_pdcch_registration');
bits=g.DCI.Bits;
assert((isnumeric(bits)||islogical(bits)) && isreal(bits) && isvector(bits) && ...
    all(bits(:)==0|bits(:)==1) && isequal(int8(bits(:)),int8(prepared.Tx.DCIBits(:))) && ...
    g.UEIndex==ue && g.RNTI==prepared.TxInfo.RNTI && ...
    double(g.TimingDecision.ControlAbsoluteSlot)==double(prepared.ReceiverConfig.lls6g.runtime.AbsoluteSlotIndex0), ...
    'sixgr:truth:ScheduledPDCCHPayloadMismatch', ...
    'Bind the actual encoded DCI bits, RNTI, UE and physical control slot; not a replacement scheduler row.');
binding=struct('Grant',g,'UEIndex',ue,'Direction',direction, ...
    'GrantContextID',string(g.PHYGrant.GrantContextId), ...
    'PayloadSHA256',string(sixgr.util.sha256Hex(typecast(int8(bits(:)),'uint8'))), ...
    'Source',"prepared_scheduled_control_not_yet_transmitted");
end
