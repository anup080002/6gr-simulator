function result=resolveLongPUCCHSROverlap(calendar,slot,startSymbol,numSymbols,priority,format)
% TS 38.213 9.2.5.1: Format 2/3/4 SR count for same-priority multiplexing.
% No pending-positive SR state or transmitted/decoded values are accepted.
% This does not decide PUSCH transport, cross-priority dropping or MAC state.
assert(isnumeric(format) && isreal(format) && isscalar(format) && ismember(format,[2 3 4]), ...
    'sixgr:truth:UnsupportedSRMultiplexFormat','Format 0/1 use different SR procedures.');
validateattributes(slot,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(startSymbol,{'numeric'},{'scalar','real','finite','integer','nonnegative'});
validateattributes(numSymbols,{'numeric'},{'scalar','real','finite','integer','positive'});
validateattributes(priority,{'numeric'},{'scalar','real','finite','integer','>=',0,'<=',1});
required={'Slot','StartSymbol','NumSymbols','PriorityIndex','SRResourceConfigurationID', ...
    'SchedulingRequestID','ULResourceAvailable','ObligationID'};
assert(istable(calendar) && all(ismember(required,calendar.Properties.VariableNames)), ...
    'sixgr:truth:InvalidSROpportunityTable','Use the configured SR opportunity table.');
for name={'UEIndex','RNTI','ServingCell','ComponentCarrier','ActiveULBWP','PUCCHConfigurationEpoch'}
    assert(ismember(name{1},calendar.Properties.VariableNames) && ...
        (isempty(calendar) || numel(unique(calendar.(name{1})))==1), ...
        'sixgr:truth:MixedSRReceiverIdentity','Resolve one receiver/BWP/configuration before counting SR bits.');
end
mask=calendar.Slot==slot & calendar.ULResourceAvailable & calendar.PriorityIndex==priority & ...
    calendar.StartSymbol<startSymbol+numSymbols & startSymbol<calendar.StartSymbol+calendar.NumSymbols;
overlap=sortrows(calendar(mask,:),{'SRResourceConfigurationID'});
ids=double(overlap.SRResourceConfigurationID);
assert(numel(unique(ids))==numel(ids),'sixgr:truth:DuplicateSRResourceConfiguration', ...
    'One SR opportunity per installed resource configuration in this slot.');
result=struct('SRResourceConfigurationIDs',ids,'SchedulingRequestIDs',double(overlap.SchedulingRequestID), ...
    'ObligationIDs',string(overlap.ObligationID),'OpportunityCount',height(overlap), ...
    'EncodedBitCount',ceil(log2(height(overlap)+1)), ...
    'Source',"configured_time_overlapping_SR_resources_no_UE_payload");
end
