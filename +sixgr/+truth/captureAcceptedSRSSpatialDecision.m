function decision=captureAcceptedSRSSpatialDecision(measurement,rnti,ri,tpmi)
% Retain the accepted tuple's published identity, not the latest detection.
% This value boundary does not itself qualify physical receiver execution.
% It identifies the gNB estimator decision, NOT the SRI resource's most
% recent occasion before PDCCH (TS 38.214 V18.8.0 6.1.1.1). Rank confirmation
% and maximum accepted-source age are simulator policy, not NR requirements.
decision=struct();
assert(isstruct(measurement) && isscalar(measurement), ...
    'sixgr:truth:AcceptedSRSSpatialIdentityMismatch','Supply one published SRS record.');
if isempty(fieldnames(measurement)), return; end
required={'MeasurementId','SignalType','TargetType','TargetId','ServingCell', ...
    'ProducerSlot','AvailableSlot','Valid','RI','PMI'};
assert(isstruct(measurement) && isscalar(measurement) && ...
    all(isfield(measurement,required)) && string(measurement.SignalType)=="SRS" && ...
    string(measurement.TargetType)=="UE" && measurement.Valid && ...
    strlength(string(measurement.MeasurementId))>0 && ...
    isequal(double(measurement.RI),double(ri)) && ...
    isequal(double(measurement.PMI),double(tpmi)), ...
    'sixgr:truth:AcceptedSRSSpatialIdentityMismatch', ...
    'The admitted RI/TPMI must belong to the exact published SRS measurement.');
decision.Version="accepted_srs_spatial_decision/v1";
decision.Source="accepted_srs_reference_measurement_not_latest_detection";
decision.RNTI=double(rnti);
fields=[string(required),"ResourceId","MeasurementSource", ...
    "SRSConfigurationContextID","SRSNumPorts","SRSConfigurationContextVersion", ...
    "SRSConfigurationEpoch","SRSResourceID","SRSResourceIDsJSON", ...
    "MeasurementClockDomain","MeasurementClockEpoch","ObservationStartSample", ...
    "ObservationEndSampleExclusive","ObservationSampleRateHz", ...
    "ResultCompletedAtSample","ResultAvailableAtSample"];
for field=fields
    if isfield(measurement,field), decision.(field)=measurement.(field); end
end
end
