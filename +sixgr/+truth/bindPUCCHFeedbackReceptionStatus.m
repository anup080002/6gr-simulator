function out=bindPUCCHFeedbackReceptionStatus(out,rx)
% Carry original receiver execution status into the scheduled HARQ owner.
% Protocol missing feedback is not a waveform DTX detection or decoded NACK.
for name=["ReceiverExecutionStatus","ReceiverUnavailableReason","FeedbackDisposition", ...
        "DetectionAttempted","DecodeAttempted","DTXDecisionAvailable"]
    if isfield(rx,name), out.(name)=rx.(name); end
end
if string(sixgr.util.structGet(rx,'ReceiverExecutionStatus',""))=="unavailable_before_synchronization"
    assert(~out.DecodeOk && ~out.DTXFlag && isempty(out.DecodedBits) && ...
        isequal(rx.DetectionAttempted,false) && isequal(rx.DecodeAttempted,false) && ...
        isequal(rx.DTXDecisionAvailable,false) && rx.DetectionOutcome=="unavailable", ...
        'sixgr:truth:InvalidUnavailableHARQReception', ...
        'An unavailable receiver cannot supply a detection decision or decoded bit.');
end
end
