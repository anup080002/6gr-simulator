function proof=verifySIB1TransmissionCompletion(owner,item)
%VERIFYSIB1TRANSMISSIONCOMPLETION Original executed SI contributor, not RX.
% A completed aggregate TX window alone cannot prove that the original SI
% component survived cancellation/replacement. No RF/channel call is made.
id='sixgr:truth:SIB1TransmissionCompletionMismatch';
assert(isa(owner,'sixgr.truth.CoupledWaveformStream') && isscalar(owner) && ...
    isstruct(item) && isscalar(item) && string(item.Kind)=="CellSIB1TX" && ...
    item.UE==0 && isstruct(item.Context) && isscalar(item.Context) && ...
    all(isfield(item.Context,{'ComponentID','ServingCell','TransmitterPlane','Prepared','EnqueueReceipt'})), ...
    id,'Require the original cell-common SI pending item and shared owner.');
c=item.Context; p=c.Prepared; r=c.EnqueueReceipt;
% Samples alone do not bind the original grid, power, clock and scheduling
% metadata later published from Prepared. Compare the complete original
% owner registration, using the same serialization as queueSIB1Transmission.
preparedContract=owner.originalSIB1PreparedContract(c.ComponentID);
assert(isstring(preparedContract) && isscalar(preparedContract) && ...
    strlength(preparedContract)==64 && ...
    preparedContract==sixgr.phy.waveform.WaveformHash.bytes(getByteStreamFromArray(p)), ...
    id,'Keep the exact original registered SI preparation, not only its sample bytes.');
for value={c.ServingCell,p.TransmitStartSample,p.NumSamples,p.TransmitEndSampleExclusive,p.SampleRateHz}
    v=value{1};
    assert(isa(v,'double') && isreal(v) && isscalar(v) && isfinite(v) && ...
        v>=0 && v<flintmax && v==fix(v),id,'Keep original exact numeric identity and sample clocks.');
end
assert(c.ServingCell>=1 && p.NumSamples>=1 && p.SampleRateHz>0,id,'Invalid SI endpoint or sample extent.');
tx="gnb_"+c.ServingCell;
assert(string(c.TransmitterPlane)==tx+":tx" && numel(item.Planes)==1 && ...
    string(item.Planes.ReceiverID)==c.TransmitterPlane, ...
    id,'SI completion must use the original gNB TX plane, not a UE receiver.');
original=owner.Events.originalEnqueueReceipt(tx,c.ComponentID);
assert(isequaln(r,original),id,'Keep the exact original owner enqueue receipt.');
samples=p.TransmitSamples; first=p.TransmitStartSample; stop=first+p.NumSamples;
assert((isa(samples,'double')||isa(samples,'single')) && ismatrix(samples) && ...
    ~isempty(samples) && all(isfinite(samples),'all') && any(samples~=0,'all') && ...
    size(samples,1)==p.NumSamples && p.TransmitEndSampleExclusive==stop && ...
    r.ContractVersion=="sixgr.waveform.enqueued_component/v1" && ...
    r.Source=="original_event_runtime_accepted_component_not_physical_execution" && ...
    isequal(r.PhysicalExecutionPerformed,false) && r.TransmitterID==tx && ...
    r.ComponentID==c.ComponentID && r.StartSample==first && r.EndSampleExclusive==stop && ...
    r.SampleRateHz==p.SampleRateHz && p.SampleRateHz==owner.SampleRateHz && ...
    r.NumTransmitAntennas==size(samples,2) && r.NumericClass==string(class(samples)) && ...
    r.OriginalSampleSHA256==sixgr.phy.waveform.WaveformHash.numeric(samples), ...
    id,'SI preparation must match the exact originally enqueued sample population.');
observation=item.Planes.Observation;
segments=item.Planes.Segments;
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer') && isscalar(observation) && ...
    observation.isComplete() && observation.StartSample==first && observation.EndSampleExclusive==stop && ...
    observation.SampleRateHz==p.SampleRateHz && observation.NumReceiveAntennas==size(samples,2) && ...
    owner.Events.NextSampleIndex==stop && iscell(segments) && ~isempty(segments), ...
    id,'Commit only the original fully completed SI TX interval on the current clock.');
actual=observation.readComplete();
cursor=first; nonzero=0; nonzeroTime=0;
trace=owner.Events.ExecutionTrace;
for k=1:numel(segments)
    s=segments{k}; e=s.Execution;
    assert(s.StartSample==cursor && s.EndSampleExclusive>cursor && s.EndSampleExclusive<=stop && ...
        e.StartSample==s.StartSample && e.EndSampleExclusive==s.EndSampleExclusive && ...
        e.SampleRateHz==p.SampleRateHz && e.ConfigurationEpoch==owner.Physical.ConfigurationEpoch && ...
        string(e.Source)=="composed_tx_retained_rf_per_link_channel_sum_receiver_noise_rf" && ...
        string(e.ApproximationMode)=="none", ...
        id,'Original successful physical intervals must cover the SI slot exactly once.');
    hit=find(cellfun(@(t)t.StartSample==s.StartSample && ...
        t.EndSampleExclusive==s.EndSampleExclusive,trace));
    assert(isscalar(hit),id,'SI interval is not uniquely retained by this event owner.');
    originalExecution=trace{hit}.Execution;
    assert(isequaln(e.ExecutedContributors,originalExecution.ExecutedContributors) && ...
        isequaln(e.TX,originalExecution.TX) && ...
        e.ConfigurationEpoch==originalExecution.ConfigurationEpoch && ...
        e.SampleRateHz==originalExecution.SampleRateHz && ...
        isequaln(e.Source,originalExecution.Source) && ...
        isequaln(e.ApproximationMode,originalExecution.ApproximationMode), ...
        id,'Do not substitute successful contributor or TX execution receipts.');
    roster=e.ExecutedContributors;
    node=roster(string({roster.TransmitterID})==tx);
    assert(isscalar(node),id,'SI requires exactly one original transmitter receipt.');
    consumed=node.Receipt;
    assert(consumed.Schema=="consumed_waveform_components/v1" && ...
        consumed.NonzeroIntervalSchema=="exact_absolute_component_nonzero_runs/v1" && ...
        isequal(consumed.CompleteContributorList,true) && ...
        consumed.StartSample==cursor && consumed.EndSampleExclusive==s.EndSampleExclusive && ...
        consumed.SampleRateHz==p.SampleRateHz && node.CommittedThroughSample>=s.EndSampleExclusive, ...
        id,'Require complete original contributor coverage, not planned component names.');
    components=consumed.Components;
    component=components(string({components.ComponentID})==c.ComponentID);
    assert(isscalar(component),id,'The originally enqueued SI component was cancelled or omitted.');
    rows=(cursor-first+1):(s.EndSampleExclusive-first);
    part=samples(rows,:); active=any(part~=0,2); edges=diff([false;active;false]);
    runs=[find(edges==1)-1 find(edges==-1)-1]+cursor;
    assert(component.OriginalSampleSHA256==r.OriginalSampleSHA256 && ...
        component.StartSample==cursor && component.EndSampleExclusive==s.EndSampleExclusive && ...
        component.NonzeroSampleCount==nnz(part) && component.NonzeroTimeSampleCount==nnz(active) && ...
        isequal(component.NonzeroIntervals,runs), ...
        id,'The original SI component samples/support were replaced or misreported.');
    % This binds the retained aggregate post-TX-RF observation, not an
    % isolated SI power claim when other components share the same interval.
    txExecution=e.TX(string({e.TX.ID})==tx);
    assert(isscalar(txExecution) && ...
        string(txExecution.Replay.RFOutputWaveformSHA256)== ...
        string(sixgr.rf.waveformSHA256(actual(rows,:))), ...
        id,'Retained TX observation samples differ from the original RF output.');
    nonzero=nonzero+component.NonzeroSampleCount;
    nonzeroTime=nonzeroTime+component.NonzeroTimeSampleCount;
    cursor=s.EndSampleExclusive;
end
assert(cursor==stop && nonzero==nnz(samples) && nonzero>0, ...
    id,'A partial emitted prefix is not a completed SI transmission.');
proof=struct('ContractVersion',"sixgr.truth.executed_SIB1_component/v1", ...
    'Source',"original_enqueued_SI_component_and_successful_shared_TX_execution", ...
    'ComponentID',string(c.ComponentID),'TransmitterID',tx, ...
    'EnqueueReceiptSHA256',string(r.ReceiptSHA256), ...
    'OriginalPreparedContractSHA256',preparedContract, ...
    'OriginalPreparedSampleSHA256',string(r.OriginalSampleSHA256), ...
    'TransmitObservationSHA256',string(observation.sampleHash()), ...
    'TransmitObservationScope',"aggregate_post_TX_RF_not_isolated_SI_power", ...
    'StartSample',first,'EndSampleExclusive',stop,'SampleRateHz',p.SampleRateHz, ...
    'PhysicalConfigurationEpoch',owner.Physical.ConfigurationEpoch, ...
    'CompletedAtSample',owner.Events.NextSampleIndex,'ExecutedIntervalCount',numel(segments), ...
    'ExecutedComponentNonzeroSampleCount',nonzero, ...
    'ExecutedComponentNonzeroTimeSampleCount',nonzeroTime, ...
    'PhysicalTransmissionVerified',true,'ReceiverExecutionClaimed',false);
end
