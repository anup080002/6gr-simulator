function binding=bindPowerWithheldPUCCHForPUSCH(audit,trace,selection,grant,book,clock)
% Validate original value-state identities; this is NOT receiver/TX proof.
% The caller separately owns the actual selection, completed capture and
% absence of prepared/executed UE samples. Never re-resolve current power.
id='sixgr:truth:PowerWithheldPUCCHBinding';
assert(istable(audit)&&istable(trace)&&isstruct(selection)&&isscalar(selection)&& ...
    isstruct(grant)&&isscalar(grant)&&isstruct(clock)&&isscalar(clock),id,'Require original scalar contracts.');
required=["UEIndex","ServingCell","RNTI","BaseStationID","ComponentCarrier","ActiveULBWP", ...
    "SweepPointIndex","DecisionSlot","PUCCHResourceSlot","DecisionSample","ClockEpoch","SampleRateHz", ...
    "MeasuredPowerReferenceRequired","PreparationAdmitted","UETransmissionPrepared", ...
    "ObservationID","PhysicalOccasionID","SelectedGNBTransport","UEProducerDisposition", ...
    "PUCCHGrantIDsJSON","CSIReportIdentitiesJSON","Source","EvidenceClass","Action","PowerReferenceStatus"];
assert(all(ismember(required,string(audit.Properties.VariableNames))),id,'Missing original admission operands.');
observation=localText(selection.PUCCHObservationID,false,id);
assert(isstring(audit.ObservationID)&&iscolumn(audit.ObservationID),id,'Keep original observation text.');
hit=find(audit.ObservationID==observation);
assert(isscalar(hit),id,'Require exactly one retained power admission.');
a=audit(hit,:);
for n=["UEIndex","ServingCell","RNTI","BaseStationID","ComponentCarrier","ActiveULBWP", ...
        "SweepPointIndex","DecisionSlot","PUCCHResourceSlot","DecisionSample","ClockEpoch","SampleRateHz"]
    localNumber(a.(n),id);
end
for n=["MeasuredPowerReferenceRequired","PreparationAdmitted","UETransmissionPrepared"]
    assert(islogical(a.(n))&&isscalar(a.(n)),id,'Admission flags must remain original logical values.');
end
for n=["ObservationID","PhysicalOccasionID","SelectedGNBTransport","UEProducerDisposition", ...
        "PUCCHGrantIDsJSON","CSIReportIdentitiesJSON","Source","EvidenceClass","Action","PowerReferenceStatus"]
    localText(a.(n),false,id);
end
assert(a.MeasuredPowerReferenceRequired && ~a.PreparationAdmitted && ~a.UETransmissionPrepared && ...
    a.SelectedGNBTransport=="PUSCH" && ...
    a.Source=="original_PUCCH_reference_preparation_admission" && ...
    a.EvidenceClass=="preparation_admission_not_PHY_execution" && ...
    a.Action=="defer_PUCCH_unavailable_measured_power_reference" && ...
    a.UEProducerDisposition=="closed_untransmitted_missing_measured_power_reference" && ...
    ismember(a.PowerReferenceStatus,["no_measurements","no_matching_measurement", ...
        "future_measurement_not_available","stale","no_available_decoded_sib1_power", ...
        "reference_lifecycle_unavailable"]),id, ...
    'A missing producer alone cannot authorize a power-withheld disposition.');
if a.PowerReferenceStatus=="reference_lifecycle_unavailable"
    assert(all(ismember(["PathlossReferenceLifetime","ReferenceLifecycleStatus"], ...
        string(a.Properties.VariableNames))),id,'Retain original unavailable lifecycle authority.');
    mode=localText(a.PathlossReferenceLifetime,false,id);
    status=localText(a.ReferenceLifecycleStatus,false,id);
    assert(mode=="retained_filtered_reference" && any(status==[ ...
        "no_received_reference_power_lifecycle","reference_configuration_changed", ...
        "serving_reference_not_synchronized","decoded_common_reference_context_mismatch", ...
        "decoded_common_reference_not_available","decoded_common_physical_epoch_changed", ...
        "future_lifecycle_installation_not_available", ...
        "received_power_change_not_installed","missing_original_filtered_reference_context", ...
        "no_observation_for_current_reference_power_generation"]),id, ...
        'Unknown or available lifecycle status cannot authorize no-transmission disposition.');
end
for n=["UEIndex","TargetSlot","SelectedAtSample"], localNumber(selection.(n),id); end
for n=["UEIndex","RNTI","Slot"], localNumber(grant.(n),id); end
for n=["ConfigurationEpoch","UCIConfigurationEpoch","SampleRateHz","AvailableAtSample", ...
        "ComponentCarrier","ActiveULBWP"], localNumber(clock.(n),id); end
assert(localText(selection.Source,false,id)=="gnb_scheduled_PUSCH_not_UE_transport_transfer" && ...
    localText(selection.PUCCHTransmissionID,true,id)=="" && ...
    localText(selection.ULGrantContextID,false,id)==localText(grant.PHYGrant.GrantContextId,false,id) && ...
    localText(selection.GNBControlObservationID,false,id)==localText(clock.GNBControlObservationID,false,id) && ...
    a.UEIndex==selection.UEIndex && a.UEIndex==grant.UEIndex && a.RNTI==grant.RNTI && ...
    a.PUCCHResourceSlot==selection.TargetSlot && a.PUCCHResourceSlot==grant.Slot && ...
    a.DecisionSlot<=a.PUCCHResourceSlot && a.DecisionSample==selection.SelectedAtSample && ...
    a.DecisionSample<=clock.AvailableAtSample && a.ClockEpoch==clock.ConfigurationEpoch && ...
    a.SampleRateHz==clock.SampleRateHz && a.SampleRateHz>0 && ...
    a.BaseStationID==a.ServingCell && a.ComponentCarrier==clock.ComponentCarrier && ...
    a.ActiveULBWP==clock.ActiveULBWP && ...
    localText(clock.ReceiverID,false,id)=="gnb_"+string(a.ServingCell)+"_rx:post_rf",id, ...
    'Retain the same selected grant, installed receiver and original decision clock.');
assert(isa(book,'sixgr.phy.pucch.HARQACKCodebookState')&&isscalar(book)&& ...
    ~isempty(book.Events)&&book.ConfigurationEpoch==clock.UCIConfigurationEpoch,id, ...
    'Require the original nonempty received UE codebook, not pending expected bits.');
grantIDs=localIDs(a.PUCCHGrantIDsJSON,id); reportIDs=localIDs(a.CSIReportIdentitiesJSON,id);
assert(~isempty(grantIDs),id,'The nonempty received book must retain original logical grants.');
traceNames=["PUCCHGrantId","UEIndex","RNTI","ScheduledAbsoluteSlot","BaseStationID", ...
    "ComponentCarrier","ActiveULBWP","SweepPointIndex","UETransmissionSuppressed", ...
    "UEProducerDisposition","PowerAdmissionObservationID","GrantExecutedFlag","MultiplexedOnPUSCH","UCIType"];
assert(all(ismember(traceNames,string(trace.Properties.VariableNames)))&& ...
    isstring(trace.PUCCHGrantId)&&iscolumn(trace.PUCCHGrantId),id,'Missing original grant trace identity.');
indices=zeros(numel(grantIDs),1);
for k=1:numel(grantIDs)
    index=find(trace.PUCCHGrantId==grantIDs(k));
    assert(isscalar(index),id,'Every original logical grant must occur exactly once.'); indices(k)=index;
end
rows=trace(indices,:);
assert(all(sixgr.truth.CoupledTruthRuntime.sharedPUCCHOccasionKey(rows)==a.PhysicalOccasionID),id, ...
    'Retain the original physical PUCCH occasion, not only the same slot.');
for n=["UEIndex","RNTI","BaseStationID","ComponentCarrier","ActiveULBWP","SweepPointIndex"]
    raw=rows.(n);
    assert(isnumeric(raw)&&isreal(raw)&&iscolumn(raw)&&all(isfinite(raw))&&all(raw==a.(n)),id, ...
        'Do not join another UE, cell, BWP or sweep population.');
end
assert(isnumeric(rows.ScheduledAbsoluteSlot)&&isreal(rows.ScheduledAbsoluteSlot)&& ...
    iscolumn(rows.ScheduledAbsoluteSlot)&&all(rows.ScheduledAbsoluteSlot==a.PUCCHResourceSlot),id,'Wrong original resource slot.');
for n=["UETransmissionSuppressed","GrantExecutedFlag","MultiplexedOnPUSCH"]
    assert(islogical(rows.(n))&&iscolumn(rows.(n)),id,'Preserve original producer flags.');
end
assert(all(rows.UETransmissionSuppressed)&&~any(rows.GrantExecutedFlag)&&~any(rows.MultiplexedOnPUSCH)&& ...
    isstring(rows.UEProducerDisposition)&&iscolumn(rows.UEProducerDisposition)&& ...
    all(rows.UEProducerDisposition==a.UEProducerDisposition)&& ...
    isstring(rows.PowerAdmissionObservationID)&&iscolumn(rows.PowerAdmissionObservationID)&& ...
    all(rows.PowerAdmissionObservationID==observation)&&isstring(rows.UCIType)&&iscolumn(rows.UCIType),id, ...
    'A transmitted, transferred or differently withheld producer cannot be closed here.');
for n=["RunUUID","ConfigHash"]
    if ismember(n,string(audit.Properties.VariableNames))
        assert(ismember(n,string(trace.Properties.VariableNames)),id,'Do not drop original run identity.');
        expected=localText(a.(n),true,id);
        assert(isstring(rows.(n))&&iscolumn(rows.(n))&&all(rows.(n)==expected),id,'Changed run/config identity.');
    end
end
types=lower(rows.UCIType); harq=contains(types,"harq");
assert(all(harq|types=="csi_part1_part2")&& ...
    isequal(sort(rows.PUCCHGrantId(~harq)),sort("PUCCH-CSI-"+reportIDs)),id,'Retain exact original HARQ and CSI membership.');
sixgr.truth.bindReceivedPUCCHCodebookRows(book,rows(harq,:));
binding=struct('ObservationID',observation,'Admission',a,'LogicalPUCCHGrantIdSet',strjoin(grantIDs,'|'), ...
    'UEReceivedCodebookDigest',book.Digest,'PhysicalReceiverQualified',false, ...
    'Source',"original_power_admission_and_received_event_identity_not_receiver_outcome");
end

function value=localText(value,emptyAllowed,id)
assert((isstring(value)&&isscalar(value)&&~ismissing(value))|| ...
    (ischar(value)&&(isrow(value)||isempty(value))),id,'Require original scalar text.');
value=string(value); assert(emptyAllowed||strlength(value)>0,id,'Missing original identity.');
end
function localNumber(value,id)
assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value)&& ...
    value>=0&&value==fix(value)&&value<=flintmax,id,'Require original exact nonnegative scalar coordinates.');
end
function values=localIDs(token,id)
try, raw=jsondecode(char(token)); catch, error(id,'Malformed original identity JSON.'); end
assert(isempty(raw)||(iscell(raw)&&isvector(raw)&&all(cellfun(@(x)ischar(x)&&isrow(x)&&~isempty(x),raw))),id, ...
    'Identity JSON must retain an array of strings.');
values=string(raw(:));
assert(numel(unique(values))==numel(values)&&~any(contains(values,'|')),id,'Identity list must be unique and delimiter-safe.');
end
