function cri=validateMeasuredCRI(raw,count)
% Preserve unavailable CRI; never round or select from malformed measurements.
assert(isnumeric(count) && isreal(count) && isscalar(count) && ...
    isfinite(count) && count>=1 && count==fix(count), ...
    'sixgr:mimo:InvalidCSIResourceCount', ...
    'The configured CSI resource count must be one positive integer.');
if iscell(raw) && isscalar(raw), raw=raw{1}; end
assert((isnumeric(raw)||islogical(raw)) && isreal(raw) && ...
    (isempty(raw)||isscalar(raw)), 'sixgr:mimo:InvalidCRI', ...
    'Measured CRI must be one real numeric resource index, not a vector or text.');
cri=NaN;
if isempty(raw) || isnan(raw), return; end
assert(isfinite(raw) && raw==fix(raw) && raw>=0 && raw<count, ...
    'sixgr:mimo:InvalidCRI', ...
    'Measured CRI must identify a configured resource in [0,%d]; rounding is forbidden.',count-1);
cri=double(raw);
end
