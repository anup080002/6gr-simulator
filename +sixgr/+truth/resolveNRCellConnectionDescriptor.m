function descriptor=resolveNRCellConnectionDescriptor(prepared,proof)
% Pure identity/config projection, not PHY proof.
% Actual caller first validates completed original CellMsg4 with its owner.
id='sixgr:truth:IssuedNRSRB1';p=prepared;
assert(p.ContractVersion=="prepared_cell_Msg4/v1" && ...
    proof.ContractVersion=="executed_cell_Msg4_component/v1" && ...
    proof.TemporaryCRNTI==p.TemporaryCRNTI && proof.ServingCell==p.ServingCell && ...
    proof.OriginalMsg3ReceiveReceiptSHA256==p.OriginalMsg3ReceiveReceipt.SHA256 && ...
    proof.ResponseProposalSHA256==p.ResponseProposal.SHA256,id,'Retain the original issued generation.');
execution=string(sixgr.util.structGet(p.Config,'run.executionID', ...
    sixgr.util.structGet(p.Config,'meta.executionID',"")));
assert(isscalar(execution)&&strlength(strtrim(execution))>0,id,'Original global execution identity required.');
identity=struct('ExecutionRunID',execution,'ServingCell',p.ServingCell, ...
    'TemporaryCRNTI',p.TemporaryCRNTI,'RARComponentID',p.ResponseProposal.OriginalRARComponentID, ...
    'OriginalMsg3ReceiveReceiptSHA256',p.OriginalMsg3ReceiveReceipt.SHA256);
connectionID="cell_connection/"+sixgr.l2.mac.MACHash.of(orderfields(identity));
descriptor=struct('ContractVersion',"NR_cell_connection_descriptor/v1", ...
    'ConnectionID',connectionID,'UEID',connectionID,'ExecutionRunID',execution, ...
    'ServingCell',p.ServingCell,'RNTI',p.TemporaryCRNTI, ...
    'ConfigurationEpoch',proof.PhysicalConfigurationEpoch,'ClockEpoch',proof.PhysicalConfigurationEpoch, ...
    'SampleRateHz',proof.SampleRateHz,'OriginalIdentity',identity, ...
    'OriginalMsg4ComponentID',proof.ComponentID,'RRCSetupSHA256',proof.RRCSetupSHA256);
end
