function proof=validatePUCCHObservationTransfer(rows,key)
% Validate reserved UCI lineage, NOT proof of PUSCH transmission/reception.
% No feedback rows is an unresolved expectation, not evidence of transfer.
required=["MultiplexedOnPUSCH","PUSCHGrantContextId","PUCCHGrantId", ...
    "UEIndex","RNTI","ServingCell","ComponentCarrier","ActiveULBWP"];
assert(istable(rows) && ~isempty(rows) && ...
    all(ismember(required,string(rows.Properties.VariableNames))), ...
    'sixgr:truth:PUCCHTransferEvidenceMissing', ...
    'An empty/missing feedback ledger cannot be labeled as a transfer to PUSCH.');
keys=sixgr.truth.CoupledTruthRuntime.sharedPUCCHOccasionKey(rows);
rows=rows(keys==string(key),:);
assert(~isempty(rows),'sixgr:truth:PUCCHTransferEvidenceMissing', ...
    'No feedback rows belong to this exact physical occasion.');
flag=double(rows.MultiplexedOnPUSCH);
ids=string(rows.PUSCHGrantContextId); grants=string(rows.PUCCHGrantId);
assert(all(isfinite(flag) & flag==1) && all(~ismissing(ids) & strlength(strtrim(ids))>0) && ...
    all(~ismissing(grants) & strlength(strtrim(grants))>0) && numel(unique(grants))==height(rows), ...
    'sixgr:truth:PUCCHTransferBindingMissing', ...
    'Every logical row needs an explicit PUSCH reservation and unique feedback identity.');
if ismember('RightCensored',rows.Properties.VariableNames)
    assert(all(double(rows.RightCensored)==0),'sixgr:truth:PUCCHTransferCensored', ...
        'A censored feedback row cannot prove transfer of an executed observation.');
end
proof=struct('Key',string(key),'FeedbackGrantIDs',grants, ...
    'PUSCHGrantContextIDs',ids,'Source',"pending_UCI_reservation_not_PUSCH_execution");
end
