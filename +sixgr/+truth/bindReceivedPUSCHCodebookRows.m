function binding=bindReceivedPUSCHCodebookRows(book,rows)
% UE producer identities -> transmitted Type-2 positions, never gNB feedback.
% Gap positions have no producer row. This is not received UCI/PHY evidence.
assert(isa(book,'sixgr.phy.pucch.HARQACKCodebookState') && isscalar(book) && ...
    book.CodebookType=="TYPE2_DYNAMIC" && isfield(book.ProcedureContext,'Transport') && ...
    book.ProcedureContext.Transport=="PUSCH", ...
    'sixgr:truth:MissingReceivedPUSCHCodebook','Use the received-UL-DAI Type-2 procedure.');
assert(istable(rows),'sixgr:truth:ReceivedPUSCHProducerMismatch','Use the actual producer table.');
if isempty(book.Events)
    assert(height(rows)==0,'sixgr:truth:ReceivedPUSCHProducerMismatch', ...
        'A gap-only or omitted codebook has no received DL producer.');
    eventRows=zeros(0,1);
else
    matched=sixgr.truth.bindReceivedPUCCHCodebookRows(book,rows);
    eventRows=matched.EventRowIndices;
end
positions=find(book.SourceEventIndex>0);
assert(numel(positions)==height(rows),'sixgr:truth:ReceivedPUSCHProducerMismatch', ...
    'Every real producer needs exactly one position; gaps cannot acquire producers.');
producerBits=zeros(height(rows),1);
producerBits(eventRows)=positions;
binding=struct('ProducerBitIndices',producerBits,'EventRowIndices',eventRows, ...
    'BitCount',numel(book.Bits),'ProducerCount',height(rows), ...
    'ProtocolGapBitIndices',find(book.SourceEventIndex==0), ...
    'CodebookDigest',book.Digest, ...
    'Source',"received_UE_event_positions_not_gNB_feedback_mapping");
end
