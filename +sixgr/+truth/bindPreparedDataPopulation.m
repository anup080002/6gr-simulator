function cfg=bindPreparedDataPopulation(cfg,state,grant,ue,direction,snr)
%BINDPREPAREDDATAPOPULATION Freeze source and derived coordinates before TX.
% Metadata only: never infer a population from a later receiver result, nor
% interpret a UE-derived seed or configured SNR as measured radio evidence.
assert(isstruct(state) && isscalar(state) && isfield(state,'SharedWaveformStream') && ...
    isa(state.SharedWaveformStream,'sixgr.truth.CoupledWaveformStream'), ...
    'sixgr:truth:PreparedPopulationOwnerRequired','Require the actual shared preparation clock owner.');
owner=state.SharedWaveformStream;
assert(~isempty(owner.Events) && ~isempty(owner.Physical), ...
    'sixgr:truth:PreparedPopulationOwnerRequired','The shared clock must be initialized.');
validateattributes(ue,{'numeric'},{'scalar','real','integer','positive','finite'});
validateattributes(snr,{'numeric'},{'scalar','real','finite'});
direction=upper(string(direction));
assert(isscalar(direction) && any(direction==["DL","UL"]), ...
    'sixgr:truth:PreparedPopulationDirection','Require an explicit DL or UL direction.');
assert(isequal(double(sixgr.util.structGet(grant,'UEIndex',NaN)),double(ue)) && ...
    upper(string(sixgr.util.structGet(grant,'Direction',"")))==direction, ...
    'sixgr:truth:PreparedPopulationGrantMismatch','Preparation population must identify the scheduled UE and direction.');
phy=sixgr.util.structGet(grant,'PHYGrant',struct());
id=string(sixgr.util.structGet(phy,'GrantContextId',""));
assert(isstruct(phy) && isscalar(phy) && logical(sixgr.util.structGet(phy,'IsFrozen',false)) && ...
    isscalar(id) && ~ismissing(id) && strlength(id)>0, ...
    'sixgr:truth:PreparedPopulationGrantRequired','Retain the actual frozen PHY grant identity.');
assert(upper(string(sixgr.util.structGet(phy,'Direction',"")))==direction && ...
    isequal(double(sixgr.util.structGet(phy,'ChannelStateKey.UEIndex',NaN)),double(ue)), ...
    'sixgr:truth:PreparedPopulationGrantMismatch','Frozen PHY and scheduled UE/direction must agree.');
% The scheduler's logical context is not a PHY-contract digest. Both must
% survive preparation, but only the explicit PHY alias names the frozen ID.
logicalID=string(sixgr.util.structGet(grant,'GrantContextId',""));
assert(isscalar(logicalID) && ~ismissing(logicalID), ...
    'sixgr:truth:PreparedPopulationGrantMismatch','Require a scalar logical grant identity when supplied.');
for name="PHYGrantContextId"
    value=string(sixgr.util.structGet(grant,name,""));
    assert(isscalar(value) && ~ismissing(value) && (strlength(value)==0 || value==id), ...
        'sixgr:truth:PreparedPopulationGrantMismatch','A populated grant identity alias must match the frozen PHY identity.');
end
source=sixgr.util.structGet(state,'CfgMobility',struct());
capsule=struct('Version',"prepared_data_population/v1", ...
    'Source',"shared_coordinator_before_data_preparation", ...
    'RunID',string(sixgr.util.structGet(cfg,'run.runTag',"")), ...
    'ExecutionID',string(sixgr.util.structGet(cfg,'run.executionID',"")), ...
    'ConfigHash',string(sixgr.util.structGet(cfg,'meta.configHash',"")), ...
    'ScenarioID',string(sixgr.util.structGet(cfg,'run.scenarioID',"")), ...
    'SweepPointIndex',double(sixgr.util.structGet(state,'CurrentSweepPointIndex',NaN)), ...
    'ConfiguredSNR_dB',double(snr), ...
    'SourceRandomSeed',double(sixgr.util.structGet(source,'run.seed',NaN)), ...
    'SourceChannelSeed',double(sixgr.util.structGet(source,'channel.seed',NaN)), ...
    'PreparedRandomSeed',double(sixgr.util.structGet(cfg,'run.seed',NaN)), ...
    'PreparedChannelSeed',double(sixgr.util.structGet(cfg,'channel.seed',NaN)), ...
    'UEIndex',double(ue),'Direction',direction,'GrantContextID',id, ...
    'LogicalGrantContextID',logicalID, ...
    'CapturedAtSample',double(owner.Events.NextSampleIndex), ...
    'ReceiverClockDomain',"shared_receiver_sample_clock/v1", ...
    'ReceiverClockEpoch',double(owner.Physical.ConfigurationEpoch));
for name=["SourceRandomSeed","SourceChannelSeed","PreparedRandomSeed","PreparedChannelSeed","SweepPointIndex"]
    value=capsule.(name);
    assert(isreal(value) && isscalar(value) && ...
        (isnan(value)||(isfinite(value)&&value>=0&&value==fix(value))), ...
        'sixgr:truth:PreparedPopulationCoordinate','A population coordinate must be an explicit integer or missing.');
end
token=jsonencode(sixgr.util.jsonSafeValue(capsule));
sha=string(sixgr.util.sha256Hex(uint8(unicode2native(token,'UTF-8'))));
runtime=sixgr.util.structGet(cfg,'lls6g.runtime',struct());
hasCapsule=isfield(runtime,'PreparedDataPopulation');
hasSHA=isfield(runtime,'PreparedDataPopulationSHA256');
assert(hasCapsule==hasSHA,'sixgr:truth:PreparedPopulationConflict', ...
    'Retain the original preparation capsule and digest together.');
if hasCapsule
    assert(isequaln(runtime.PreparedDataPopulation,capsule) && ...
        isequal(string(runtime.PreparedDataPopulationSHA256),sha), ...
        'sixgr:truth:PreparedPopulationConflict', ...
        'A prepared configuration cannot silently acquire another population; use the original unprepared configuration.');
end
cfg=sixgr.util.structSet(cfg,'lls6g.runtime.PreparedDataPopulation',capsule);
cfg=sixgr.util.structSet(cfg,'lls6g.runtime.PreparedDataPopulationSHA256',sha);
end
