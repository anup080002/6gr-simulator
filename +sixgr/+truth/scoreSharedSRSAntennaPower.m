function [result,evidence]=scoreSharedSRSAntennaPower(measurement,item,input,owner)
% Independent POST-reception comparison on the noisy power measurement's
% original pre-RF timing/FFT/RE/branch support. The desired-link capture is
% admitted only after its finite original component dependency is proved.
% No channel/RF replay or clean-reference input to the practical receiver.
% This is isolated emitted-SRS model power, including actual TX distortion,
% not undistorted ideal SRS or a hardware/standards accuracy qualification.
result=struct('SRSRSRPReferenceAvailable',false, ...
    'SRSRSRPReferenceStatus',"unavailable_no_same_execution_reference", ...
    'SRSRSRPReferenceSource',"",'SRSRSRPReferencePlane',"", ...
    'SRSRSRPReferencePower_dBm',NaN,'SRSRSRPEstimationError_dB',NaN, ...
    'SRSRSRPReferenceEvidenceJSON',"",'SRSRSRPReferenceEvidenceSHA256',"", ...
    'SRSRSRPReferenceErrorIdentifier',"");
evidence=struct();
if nargin==0, return; end
assert(nargin==4,'sixgr:truth:SRSRSRPReferenceArguments', ...
    'Supply the returned noisy measurement and original completed owner operands.');
if ~logical(sixgr.util.structGet(measurement,'SRSAbsolutePowerAvailable',false))
    result.SRSRSRPReferenceStatus="unavailable_no_actual_absolute_power_measurement";
    return;
end
try
    id='sixgr:truth:SRSRSRPReferenceIdentity';
    assert(isa(owner,'sixgr.truth.CoupledWaveformStream')&& ...
        string(item.Kind)=="SRS"&&isfield(item.Context,'SRSComponentBinding'),id, ...
        'Only the original completed SRS owner and frozen emitted component may qualify.');
    p=input.Prepared;
    assert(isa(p,'sixgr.link.PreparedUplinkControlTransmission')&&p.Channel=="SRS"&& ...
        isequaln(p,item.Context.Prepared),id,'Do not replace the actual SRS preparation.');
    receiver=input.Observation;
    assert(string(measurement.ReceiverObservationHashPlane)=="actual_receiver_input_before_synchronization" && ...
        string(measurement.ReceiverObservationHashSerialization)== ...
            "WaveformHash.runtimeArray_class_dimensions_real_imag_double" && ...
        string(measurement.ReceiverObservationSHA256)==receiver.sampleHash() && ...
        measurement.ObservationStartSample==receiver.StartSample && ...
        measurement.ObservationEndSampleExclusive==receiver.EndSampleExclusive && ...
        measurement.ObservationSampleRateHz==receiver.SampleRateHz,id, ...
        'Bind the input actually consumed by the returned practical receiver, not a later substitute.');
    b=item.Context.SRSComponentBinding;
    assert(string(b.ContractVersion)=="sixgr.truth.emitted_SRS_component/v1"&& ...
        string(b.ComponentID)==string(item.ID)&&b.UE==item.UE&& ...
        b.StartSample==p.StartSample&&b.EndSampleExclusive==p.EndSampleExclusive&& ...
        b.SampleRateHz==p.SampleRateHz&&b.ConfigurationEpoch==owner.Physical.ConfigurationEpoch&& ...
        owner.Events.NextSampleIndex>=b.EndSampleExclusive,id, ...
        'Retain the actual enqueued or legally replaced component identity and completed clock.');
    token=string(measurement.SRSAbsolutePowerEvidenceJSON);
    assert(strlength(token)>0&&sha(token)==string(measurement.SRSAbsolutePowerEvidenceSHA256),id, ...
        'The original noisy measurement evidence changed.');
    power=jsondecode(token);
    if ~logical(sixgr.util.structGet(power,'FFTSupportAvailable',false))
        result.SRSRSRPReferenceStatus="unavailable_original_noisy_FFT_dependency_support";
        return;
    end
    assert(isfield(power,'FFTSupport')&&string(power.WaveformAmplitudeUnit)=="sqrt_mW"&& ...
        string(power.ObservationID)==string(item.ID)&& ...
        power.PhysicalConfigurationEpoch==owner.Physical.ConfigurationEpoch&& ...
        power.Resource.ResourceID==p.Metadata.SRSConfig.ResourceId&& ...
        string(power.Resource.ConfigHash)==string(p.Metadata.SRSConfig.ConfigHash)&& ...
        power.SRSNumPorts==p.Tx.SRS.NumSRSPorts,id, ...
        'Reference and estimator must share the original installed resource, unit and epoch.');
    ids=string({item.Planes.ReceiverID});
    preIndex=find(ids==string(power.PlaneID));
    desiredIndex=find(ids==string(item.Context.DesiredReferencePlane));
    assert(isscalar(preIndex)&&isscalar(desiredIndex)&& ...
        item.Planes(preIndex).Observation==input.PhysicalMeasurementObservation&& ...
        item.Planes(desiredIndex).Observation==input.DesiredReferenceObservation,id, ...
        'No same-shaped buffer, post-RF signal, or later transformed NMSE reference may replace original planes.');
    pre=input.PhysicalMeasurementObservation; desired=input.DesiredReferenceObservation;
    source=input.DesiredReferenceEvidence;
    assert(pre.isComplete()&&desired.isComplete()&& ...
        pre.StartSample==power.ObservationStartSample&&pre.EndSampleExclusive==power.ObservationEndSampleExclusive&& ...
        pre.SampleRateHz==power.ObservationSampleRateHz&&pre.sampleHash()==string(power.ObservationSHA256)&& ...
        desired.StartSample==pre.StartSample&&desired.EndSampleExclusive==pre.EndSampleExclusive&& ...
        desired.SampleRateHz==pre.SampleRateHz&&desired.NumReceiveAntennas==pre.NumReceiveAntennas&& ...
        string(source.Source)=="actual_executed_link_contribution"&& ...
        string(source.TransmitterID)==string(b.TransmitterID)&& ...
        string(source.ReceiverID)==string(power.ReceiverID)&& ...
        source.StartSample==pre.StartSample&&source.EndSampleExclusive==pre.EndSampleExclusive&& ...
        ~source.ReceiverEstimatorInput&&source.AdditionalRFExecutions==0&&source.AdditionalChannelExecutions==0,id, ...
        'The independent reference must be this original desired-link contribution on the same receiver clock.');
    branch=sixgr.rf.validateReceiveBranchObservation(pre,input.Replay, ...
        owner.Physical.receiveBranchLayout(string(source.ReceiverID)));
    assert(branch.Available&&power.ReceiveBranchBinding.Available&& ...
        string(branch.Layout.LayoutSHA256)==string(power.ReceiveBranchBinding.Layout.LayoutSHA256)&& ...
        string(branch.ReferencePlane)==string(power.ReferencePlane),id, ...
        'Both operands must use the original executed identity-combined modeled receive branches.');
    support=double(power.ResourceSupportSubcarrier0Symbol0);
    if isvector(support)&&numel(support)==2, support=reshape(support,1,2); end
    fftSupport=power.FFTSupport;
    if isvector(fftSupport.FFTIntervals)&&numel(fftSupport.FFTIntervals)==2
        fftSupport.FFTIntervals=reshape(fftSupport.FFTIntervals,1,2);
    end
    retainedSupport=double(fftSupport.ResourceSupportSubcarrier0Symbol0);
    if isvector(retainedSupport)&&numel(retainedSupport)==2, retainedSupport=reshape(retainedSupport,1,2); end
    assert(string(fftSupport.ContractVersion)=="sixgr.srs.measured_native_FFT_support/v1" && ...
        string(fftSupport.Source)=="original_noisy_preRF_measurement_native_demodulation" && ...
        fftSupport.ObservationStartSample==pre.StartSample && ...
        fftSupport.ObservationEndSampleExclusive==pre.EndSampleExclusive && ...
        isequal(retainedSupport,support) && ...
        string(fftSupport.AlignedWaveformSHA256)==string(power.AlignedWaveformSHA256) && ...
        string(fftSupport.GridSHA256)==string(power.ReceivedGridSHA256) && ...
        ~fftSupport.ReferenceTimingAcquisitionUsed && ~fftSupport.ReceiveResamplingApplied,id, ...
        'The support subcapsule must bind this original noisy measurement, not another plane or grid.');
    isolation=sixgr.truth.sharedSRSComponentIsolation(item,input,owner,fftSupport.FFTIntervals);
    if ~isolation.Available
        result.SRSRSRPReferenceStatus=string(isolation.Status);
        evidence=struct('Isolation',isolation,'MeasurementEvidenceSHA256',sha(token));
        [result.SRSRSRPReferenceEvidenceJSON,result.SRSRSRPReferenceEvidenceSHA256]=encode(evidence);
        return;
    end
    % Only the already measured offset is used. No clean timing estimate,
    % AGC inverse, CFO transform, channel estimate, or transmitter EPRE.
    offset=double(power.Timing.AppliedTimingCorrectionSamples);
    count=double(power.Timing.DemodulatedSampleCount);
    original=desired.readComplete();
    assert(offset>=0&&offset==fix(offset)&&count>0&&count==fix(count)&& ...
        offset+count<=size(original,1),id,'The original reference cannot be padded.');
    [grid,ofdm]=sixgr.phy.waveform.ofdmDemodulate(p.Tx.Carrier,original(offset+(1:count),:), ...
        'Nfft',double(fftSupport.Nfft),'SampleRate',double(fftSupport.SampleRateHz), ...
        'CyclicPrefixFraction',double(fftSupport.CyclicPrefixFraction),'Windowing',0);
    actualSupport=sixgr.phy.srs.srsAntennaPowerFFTSupport(p.Tx.Carrier,ofdm,power.Timing, ...
        pre.StartSample,pre.EndSampleExclusive,support);
    for name=["FFTIntervals","SampleRateHz","Nfft","CarrierSlot","SymbolsPerSlot", ...
            "SlotsPerSubframe","CyclicPrefixFraction","AppliedTimingCorrectionSamples","AlignedSampleCount"]
        assert(isequal(double(actualSupport.(name)),double(fftSupport.(name))),id, ...
            'The reference must use exactly the recorded noisy estimator FFT support.');
    end
    assert(isequal(double(actualSupport.SymbolLengths(:)),double(fftSupport.SymbolLengths(:)))&& ...
        isequal(double(actualSupport.CyclicPrefixLengths(:)),double(fftSupport.CyclicPrefixLengths(:)))&& ...
        power.Nfft==ofdm.Nfft&&power.RawGridScaleToSqrtW==1/(double(ofdm.Nfft)*sqrt(1000)),id, ...
        'Preserve native FFT dimensions and raw sqrt(mW)-to-sqrt(W) normalization.');
    K=size(grid,1); L=size(grid,2);
    indices=nrSRSIndices(p.Tx.Carrier,p.Tx.SRS); symbols=nrSRS(p.Tx.Carrier,p.Tx.SRS);
    [k,l,~]=ind2sub([K,L,double(p.Tx.SRS.NumSRSPorts)],double(indices(:)));
    assert(isequal(support,unique([k l]-1,'rows','sorted'))&& ...
        string(power.ReferenceSymbolSHA256)==sixgr.phy.waveform.WaveformHash.numeric(symbols),id, ...
        'Use the actual SRS physical-RE union once, including coincident ports.');
    measuredW=double(power.PerReceiveBranch_W(:).');
    comparison=sixgr.phy.srs.compareSRSAntennaPower(grid,support,ofdm.Nfft,measuredW);
    if comparison.ReferenceReported_W<=0
        result.SRSRSRPReferenceStatus="unavailable_no_positive_isolated_reference_power";
        return;
    end
    assert(comparison.MeasuredReported_W==power.Reported_W&& ...
        comparison.MeasuredSelectedBranch0==power.SelectedBranch0&& ...
        measurement.SRS_RSRP_dBm==10*log10(comparison.MeasuredReported_W)+30,id, ...
        'Do not replace the published measured branch policy.');
    result.SRSRSRPReferenceAvailable=true;
    result.SRSRSRPReferenceStatus="available_isolated_emitted_SRS_model_comparison_not_accuracy_qualified";
    result.SRSRSRPReferenceSource="original_isolated_emitted_SRS_desired_link_RE_power";
    result.SRSRSRPReferencePlane=string(branch.ReferencePlane);
    result.SRSRSRPReferencePower_dBm=comparison.ReferencePower_dBm;
    result.SRSRSRPEstimationError_dB=comparison.ReportedError_dB;
    evidence=struct('ContractVersion',"sixgr.srs.same_execution_RSRP_comparison/v1", ...
        'Source',result.SRSRSRPReferenceSource,'ReferencePlane',result.SRSRSRPReferencePlane, ...
        'EmittedComponent',b,'MeasurementEvidenceSHA256',sha(token), ...
        'DesiredReferenceObservationSHA256',desired.sampleHash(), ...
        'DesiredReferenceAlignedSHA256',ofdm.WaveformSHA256,'DesiredReferenceGridSHA256',ofdm.GridSHA256, ...
        'FFTSupport',fftSupport,'ReceiveBranchLayoutSHA256',branch.Layout.LayoutSHA256, ...
        'Isolation',isolation, ...
        'IncludesOriginalTXRFNonlinearity',true,'IncludesReceiverRF',false, ...
        'IdealUndistortedReference',false,'HardwareConformanceQualified',false, ...
        'AccuracyQualified',false,'ReferenceUsedByReceiver',false, ...
        'AdditionalChannelExecutions',0,'AdditionalRFExecutions',0,'ReferenceTimingAcquisitionUsed',false);
    for name=string(fieldnames(comparison)).', evidence.(name)=comparison.(name); end
    [result.SRSRSRPReferenceEvidenceJSON,result.SRSRSRPReferenceEvidenceSHA256]=encode(evidence);
catch cause
    % Optional post-reception evidence cannot invalidate a usable practical
    % SRS report or publish partially computed reference/error numbers.
    result=sixgr.truth.scoreSharedSRSAntennaPower(); evidence=struct();
    result.SRSRSRPReferenceStatus="unavailable_original_reference_proof_failed";
    result.SRSRSRPReferenceErrorIdentifier=string(cause.identifier);
end
end

function value=sha(token)
value=string(sixgr.rrc.asn1.asn1SHA256Hex(unicode2native(char(token),'UTF-8')));
end

function [token,digest]=encode(evidence)
token=string(jsonencode(evidence)); digest=sha(token);
end
