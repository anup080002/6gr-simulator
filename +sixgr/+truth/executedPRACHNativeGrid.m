function [grid, domain] = executedPRACHNativeGrid(tx)
% Retained native-grid ownership; never reinterpret indices as carrier REs.
required={'Carrier','PRACH','Grid','Indices','Waveform','OFDMInfo','WaveformPortResourceGrid'};
assert(isstruct(tx) && all(isfield(tx,required)), ...
    'sixgr:truth:MissingPRACHNativeEvidence','Executed PRACH must retain native grid, indices and waveform-port mapping.');
native=tx.Grid; idx=tx.Indices;
assert(isnumeric(idx) && isreal(idx) && all(isfinite(idx(:))) && ...
    all(idx(:)>=1 & idx(:)<=numel(native) & idx(:)==fix(idx(:))), ...
    'sixgr:truth:InvalidPRACHNativeIndices','PRACH indices must address its native grid exactly.');
expected=nrPRACHIndices(tx.Carrier,tx.PRACH);
assert(isequal(sort(double(idx(:))),sort(double(expected(:)))) && ...
    isequal(sort(double(find(native~=0))),sort(double(idx(:)))), ...
    'sixgr:truth:PRACHNativeOwnershipMismatch','Retained PRACH ownership differs from the transmitted native grid.');
grid=tx.WaveformPortResourceGrid;
assert(size(grid,1)==size(native,1) && size(grid,2)==size(native,2) && ...
    size(grid,3)==size(tx.Waveform,2) && all(isfinite(grid),'all'), ...
    'sixgr:truth:PRACHNativePortMismatch','PRACH waveform-port grid dimensions disagree with the actual TX.');
assert(isequaln(grid,repmat(native,1,1,size(grid,3))/sqrt(size(grid,3))), ...
    'sixgr:truth:PRACHWaveformPortMappingMismatch','Retained waveform-port grid differs from the executed equal-phase PRACH replication.');
domain="waveform_port_before_spatial_projection";
if isfield(tx,'TransmitPortResourceGrid')
    assert(isfield(tx,'TransmitProjectionMatrix') && isfield(tx,'TransmitProjectionMatrixSHA256'), ...
        'sixgr:truth:MissingPRACHSpatialAuthority','Physical PRACH grid requires the actual applied matrix.');
    matrix=tx.TransmitProjectionMatrix;
    assert(size(matrix,2)==size(grid,3) && all(isfinite(matrix),'all') && ...
        string(sixgr.phy.mimo.MatrixContract.digest(matrix))==string(tx.TransmitProjectionMatrixSHA256), ...
        'sixgr:truth:PRACHSpatialAuthorityMismatch','Applied PRACH projection dimensions/hash disagree.');
    mapped=reshape(reshape(grid,[],size(grid,3))*cast(matrix,'like',grid).',size(grid,1),size(grid,2),size(matrix,1));
    assert(isequaln(mapped,tx.TransmitPortResourceGrid), ...
        'sixgr:truth:PRACHSpatialGridMismatch','Physical PRACH resource grid differs from its retained applied mapping.');
    grid=mapped;
    domain="physical_antenna_normalized_grid_before_power_and_rf";
end
end
