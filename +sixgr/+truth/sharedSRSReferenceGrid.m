function [grid,evidence]=sharedSRSReferenceGrid(prepared,captures,replay,timing,ofdmInfo)
% Scoring ONLY: executed fading/filter response on the practical RX clock.
% Reference excludes RF distortion; includes declared TX scaling, physical
% port mapping and executed propagation loss. No receiver-derived gain fit.
assert(isa(prepared,'sixgr.link.PreparedUplinkControlTransmission') && ...
    prepared.Channel=="SRS" && iscell(captures) && ~isempty(captures), ...
    'sixgr:truth:MissingSRSChannelScoring','Retain the prepared SRS and actual channel reference segments.');
first=captures{1}; base=first.Reference; gains=cell(size(captures)); times=gains;
next=base.StartSample;
for n=1:numel(captures)
    c=captures{n}; r=c.Reference;
    assert(c.LinkID==first.LinkID && c.TX==first.TX && c.RX==first.RX && ...
        r.Source=="same_executed_NR_channel_path_gains_and_filters" && ...
        r.StartSample==next && size(r.PathGains,1)==r.EndSampleExclusive-r.StartSample && ...
        r.SampleRateHz==prepared.SampleRateHz && r.StateKey==base.StateKey && ...
        isequal(r.PathFilters,base.PathFilters) && ...
        r.NormalizeChannelOutputs==base.NormalizeChannelOutputs && ...
        r.NumTransmitAntennas==prepared.NumPhysicalTransmitAntennas && ...
        r.NumReceiveAntennas==prepared.NumReceiveAntennas && ...
        r.AdditionalChannelExecutions==0 && ~r.ReceiverEstimatorInput, ...
        'sixgr:truth:IncompleteSRSChannelScoring','Do not bridge a gap, change link/ports or replace missing channel coefficients.');
    gains{n}=r.PathGains; times{n}=r.SampleTimes_s; next=r.EndSampleExclusive;
end
gains=cat(1,gains{:}); times=vertcat(times{:});
start=prepared.StartSample-base.StartSample;
aligned=prepared.ReceiveStartSample+double(timing.AppliedTimingCorrectionSamples);
offset=aligned-prepared.StartSample;
assert(start>=0 && start==fix(start) && offset>=0 && offset==fix(offset) && ...
    offset<size(base.PathFilters,1) && ...
    next>=aligned+double(timing.DemodulatedSampleCount) && ...
    all(abs(diff(times)*prepared.SampleRateHz-1)<1e-6), ...
    'sixgr:truth:SRSReferenceTimingCoverage','Reference coefficients must cover the actual TX origin and measured RX demodulation interval.');
gains=gains(start+1:end,:,:,:); times=times(start+1:end);
grid=nrPerfectChannelEstimate(prepared.Tx.Carrier,gains,base.PathFilters,offset,times, ...
    'SampleRate',prepared.SampleRateHz,'CyclicPrefixFraction',ofdmInfo.CyclicPrefixFraction);
L=double(prepared.Tx.Carrier.SymbolsPerSlot);
assert(size(grid,2)==L,'sixgr:truth:SRSReferenceSlotShape','Score exactly the received SRS slot, not a truncated or extended grid.');
array=sixgr.rf.AntennaArrayFactory.build(prepared.ReceiverConfig,'ue', ...
    'signal','srs','numPorts',size(prepared.Tx.Waveform,2));
W=array.PortToElementMatrix;
assert(size(W,1)==size(grid,4) && size(grid,3)==prepared.NumReceiveAntennas, ...
    'sixgr:truth:SRSReferencePortMapping','Reference must use the prepared physical transmit map.');
amplitude=double(prepared.Tx.PowerContext.AmplitudeScale);
loss=10^(double(replay.AppliedLargeScaleGain_dB)/20);
assert(isscalar(amplitude) && isfinite(amplitude) && amplitude>0 && ...
    isscalar(loss) && isfinite(loss) && loss>0, ...
    'sixgr:truth:SRSReferencePowerUnavailable','Retain actual declared transmit scaling and applied link loss.');
normalization=1;
if base.NormalizeChannelOutputs, normalization=1/sqrt(base.NumReceiveAntennas); end
K=size(grid,1); R=size(grid,3); P=size(W,2);
grid=reshape(reshape(grid,[],size(W,1))*W,[K L R P])*amplitude*loss*normalization;
evidence=struct('Source',"applied_channel_gain_truth_shared_NR_path_filter_reference", ...
    'ReferencePlane',"nominal_linear_SRS_port_response_with_executed_fading_loss_and_declared_TX_power", ...
    'RFImpairmentsIncluded',false,'ReceiverEstimatorInput',false, ...
    'TimingSource',string(timing.TimingSource),'TimingOffsetRelativeTX_samples',offset, ...
    'TXStartSample',prepared.StartSample,'ReceiverAlignedStartSample',aligned, ...
    'PortToElementMatrix',W,'TXAmplitudeScale',amplitude,'LargeScaleAmplitudeGain',loss, ...
    'ChannelOutputNormalizationGain',normalization,'ChannelReferenceSegmentCount',numel(captures), ...
    'GainOrPhaseFitted',false,'AdditionalChannelExecutions',0);
end
