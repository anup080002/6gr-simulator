function power=bindReceivedPUCCHPowerState(configured,spatial,planned,owner,proposal)
% Draft adapter: freeze a read-only received-owner proposal into TX power.
% This does NOT install/ingest/commit any command or qualify a transmission.
assert(isa(owner,'sixgr.link.ReceivedPUCCHPowerControlState') && isscalar(owner) && ...
    isa(configured,'sixgr.phy.pucch.PUCCHPowerControlState') && ...
    isa(spatial,'sixgr.phy.pucch.PUCCHSpatialRelationState') && ...
    isstruct(planned) && isfield(planned,'Plan') && ...
    isa(planned.Plan,'sixgr.phy.pucch.PUCCHResourcePlan'), ...
    'sixgr:truth:ReceivedPUCCHPowerBinding','Require original typed owner, plan and power.');
assert(isstruct(proposal) && isscalar(proposal) && isfield(proposal,'Occasion') && ...
    isequaln(proposal,owner.resolveOccasion(proposal.Occasion)), ...
    'sixgr:truth:ReceivedPUCCHPowerBinding','A supplied digest alone is not an original owner proposal.');
b=owner.Installation; o=proposal.Occasion; plan=planned.Plan; d=configured.Data;
assert(string(sixgr.util.structGet(d,'OperatingPointAuthority','absolute_power_control'))== ...
    "absolute_power_control",'sixgr:truth:ReceivedPUCCHPowerBinding', ...
    'Do not apply an absolute TPC adjustment to normalized fixed-EsN0 power.');
for field=["UEID","RNTI","ServingCell","ComponentCarrier","ActiveULBWP"]
    assert(isequal(double(plan.Data.(field)),double(b.(field))) && ...
        isequal(double(o.(field)),double(b.(field))), ...
        'sixgr:truth:ReceivedPUCCHPowerBinding','Original endpoint/BWP ownership changed.');
end
assert(o.ResourceID==plan.Resource.ID && string(o.ResourceDigest)==string(plan.Resource.Digest) && ...
    string(o.ReportDigest)==string(plan.ReportDigest) && ...
    isequal(planned.Report.Digest,plan.ReportDigest) && ...
    o.StartSymbolBoundary==14*(plan.Data.DueSlot-1)+plan.Resource.Data.StartSymbol && ...
    spatial.Data.P0PUCCHID==b.P0PUCCHID && spatial.Data.ClosedLoopIndex==b.ClosedLoopIndex && ...
    d.P0dBm==b.P0_dBm && d.Mu==log2(b.SubcarrierSpacingKHz/15), ...
    'sixgr:truth:ReceivedPUCCHPowerBinding','Freeze the selected original resource, report, P0 and loop.');
d.ConfiguredClosedLoopAdjustmentdB=d.ClosedLoopAdjustmentdB;
d.ConfiguredTPCCommandSource=d.TPCCommandSource;
d.ClosedLoopAdjustmentdB=proposal.UpdatedG_dB;
d.TPCCommandSource="received_connected_DCI_occasion_indexed_g";
d.StateID="PUCCH-RECEIVED-POWER-"+string(proposal.Digest);
d.ReceivedPowerInstallationDigest=proposal.InstallationDigest;
d.ReceivedPowerProposal=proposal;
d.ReceivedPowerProposalDigest=proposal.Digest;
d.ReceivedPowerStateCommitted=false;
d.PhysicalExecutionQualified=false;
power=sixgr.phy.pucch.PUCCHPowerControlState(d);
end
