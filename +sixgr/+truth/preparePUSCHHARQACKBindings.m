function binding=preparePUSCHHARQACKBindings(pending,trace,timeline,contract)
% Read-only validation of the entire legacy PUSCH feedback reservation.
% This prevents a bad later row from failing after earlier HARQ mutation.
% It does NOT qualify the legacy row-to-bit mapping as independent Type-2.
required={'GrantIDs','SourceSlots','HARQIDs','ExpectedBits','TransmissionSlot', ...
    'DeliverySlot','GrantContextID','UEIndex','RNTI'};
assert(isstruct(contract) && isscalar(contract) && all(isfield(contract,required)), ...
    'sixgr:truth:InvalidPUSCHHARQACKBinding','Retain the complete reservation contract.');
ids=string(contract.GrantIDs(:)); n=numel(ids);
assert(n>0 && ~any(ismissing(ids)) && all(strlength(strtrim(ids))>0) && ...
    numel(unique(ids))==n && numel(contract.SourceSlots)==n && ...
    numel(contract.HARQIDs)==n && numel(contract.ExpectedBits)==n, ...
    'sixgr:truth:InvalidPUSCHHARQACKBinding','Every reserved bit needs one unique binding.');
localIntegers(contract.SourceSlots,1); localIntegers(contract.HARQIDs,0);
localFlag(contract.ExpectedBits,false);
for field=["TransmissionSlot","DeliverySlot","UEIndex","RNTI"]
    value=contract.(field); localIntegers(value,1);
    assert(isscalar(value),'sixgr:truth:InvalidPUSCHHARQACKBinding','Use one feedback owner and clock.');
end
assert(contract.DeliverySlot>=contract.TransmissionSlot && ...
    all(contract.SourceSlots<=contract.TransmissionSlot), ...
    'sixgr:truth:InvalidPUSCHHARQACKRuntimeBinding','Feedback cannot precede its source or transmission.');
context=string(contract.GrantContextID);
assert(isscalar(context) && ~ismissing(context), ...
    'sixgr:truth:InvalidPUSCHHARQACKBinding','Use a scalar grant context identity.');
pfields={'PUCCHGrantId','Processed','Direction','UEIndex','RNTI','HarqID','SourceSlot','DueSlot','Ack'};
tfields={'PUCCHGrantId','MultiplexedOnPUSCH','GrantExecutedFlag'};
assert(istable(pending) && ~isempty(pending) && all(ismember(pfields,pending.Properties.VariableNames)) && ...
    istable(trace) && ~isempty(trace) && all(ismember(tfields,trace.Properties.VariableNames)), ...
    'sixgr:truth:MissingPUSCHHARQACKRuntimeRows','Retain pending and transferred control-grant rows.');
processed=localFlag(pending.Processed,false);
multiplexed=localFlag(trace.MultiplexedOnPUSCH,false);
executed=localFlag(trace.GrantExecutedFlag,false);
binding=repmat(struct('PendingIndex',NaN,'TraceIndex',NaN,'TimelineIndex',NaN, ...
    'RNTI',NaN,'UEIndex',NaN,'SourceSlot',NaN,'HARQID',NaN,'ExpectedAck',false),n,1);
for k=1:n
    pi=find(string(pending.PUCCHGrantId)==ids(k) & ~processed);
    ti=find(string(trace.PUCCHGrantId)==ids(k) & multiplexed & ~executed);
    assert(isscalar(pi) && isscalar(ti),'sixgr:truth:InvalidPUSCHHARQACKRuntimeRows', ...
        'PUSCH feedback grant %s must bind one pending row and one transferred row.',ids(k));
    row=pending(pi,:);
    source=localNumber(row,'SourceSlot',1); pid=localNumber(row,'HarqID',0);
    ue=localNumber(row,'UEIndex',1); rnti=localNumber(row,'RNTI',1);
    due=localNumber(row,'DueSlot',1); ack=localFlag(row.Ack,true);
    rowContext="";
    if ismember('PUSCHGrantContextId',row.Properties.VariableNames), rowContext=string(row.PUSCHGrantContextId); end
    assert(isscalar(rowContext) && ~ismissing(rowContext) && ...
        upper(string(row.Direction))=="DL" && source==contract.SourceSlots(k) && ...
        pid==contract.HARQIDs(k) && due==contract.TransmissionSlot && ...
        ue==contract.UEIndex && rnti==contract.RNTI && ack==logical(contract.ExpectedBits(k)) && ...
        (strlength(strtrim(rowContext))==0 || strlength(strtrim(context))==0 || rowContext==context), ...
        'sixgr:truth:InvalidPUSCHHARQACKRuntimeBinding', ...
        'PUSCH feedback grant %s has an inconsistent source, owner, clock or reservation.',ids(k));
    timelineIndex=NaN;
    if istable(timeline) && ~isempty(timeline)
        assert(all(ismember({'Direction','RNTI','HarqID','Slot'},timeline.Properties.VariableNames)), ...
            'sixgr:truth:InvalidPUSCHHARQACKTimelineBinding','Retain originating HARQ timeline identities.');
        hit=find(upper(string(timeline.Direction))=="DL" & ...
            double(timeline.RNTI)==rnti & double(timeline.HarqID)==pid & double(timeline.Slot)==source);
        assert(isscalar(hit),'sixgr:truth:InvalidPUSCHHARQACKTimelineBinding', ...
            'PUSCH feedback grant %s must resolve one originating DL timeline row.',ids(k));
        timelineIndex=hit;
    end
    binding(k)=struct('PendingIndex',pi,'TraceIndex',ti,'TimelineIndex',timelineIndex, ...
        'RNTI',rnti,'UEIndex',ue,'SourceSlot',source,'HARQID',pid,'ExpectedAck',ack);
end
keys=[[binding.RNTI].' [binding.HARQID].' [binding.SourceSlot].'];
assert(size(unique(keys,'rows'),1)==n,'sixgr:truth:InvalidPUSCHHARQACKRuntimeBinding', ...
    'A process attempt cannot consume two reserved feedback bits.');
end

function value=localNumber(row,name,minimum)
value=row.(name); if iscell(value) && isscalar(value), value=value{1}; end
localIntegers(value,minimum);
assert(isscalar(value),'sixgr:truth:InvalidPUSCHHARQACKRuntimeBinding','Use scalar row identities.');
value=double(value);
end

function localIntegers(value,minimum)
assert(isnumeric(value) && isreal(value) && (isvector(value)||isempty(value)) && ...
    all(isfinite(value(:))) && all(value(:)==fix(value(:))) && all(value(:)>=minimum), ...
    'sixgr:truth:InvalidPUSCHHARQACKRuntimeBinding','Reservation identities must be exact numeric integers.');
end

function value=localFlag(value,scalar)
assert((islogical(value)||isnumeric(value)) && isreal(value) && ...
    (isvector(value)||isempty(value)) && (~scalar||isscalar(value)) && ...
    all(isfinite(value(:))) && all(value(:)==0|value(:)==1), ...
    'sixgr:truth:InvalidPUSCHHARQACKEvidence','Feedback flags and bits must be binary before conversion.');
value=logical(value(:));
end
