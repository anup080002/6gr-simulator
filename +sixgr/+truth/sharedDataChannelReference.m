function [grid,evidence]=sharedDataChannelReference(snapshot,prepared,captures,replays,projection)
% Independent post-decode reference from the SAME executed channel samples.
% Includes applied TX power/precoder/loss and actual RX linear operations.
% This is the nominal linear channel, not a replacement for distorted IQ.
channel="PUSCH";
if prepared.Direction=="DL", channel="PDSCH"; end
assert(any(prepared.Direction==["DL","UL"]) && iscell(captures) && ~isempty(captures) && ...
    numel(captures)==numel(replays) && ...
    snapshot.Contract==channel+"_pilot_channel_capture/v1", ...
    'sixgr:truth:MissingPUSCHChannelReference','Retain actual UL receiver and channel execution evidence.');
base=captures{1}.Reference; first=captures{1}; next=base.StartSample;
gains=cell(size(captures)); times=gains; losses=zeros(numel(captures),1);
for k=1:numel(captures)
    c=captures{k}; r=c.Reference;
    assert(c.LinkID==first.LinkID && c.TX==first.TX && c.RX==first.RX && ...
        sixgr.channel.isAppliedChannelReference(r) && r.Source==base.Source && ...
        r.StartSample==next && size(r.PathGains,1)==r.EndSampleExclusive-r.StartSample && ...
        r.SampleRateHz==prepared.SampleRateHz && r.StateKey==base.StateKey && ...
        isequal(r.PathFilters,base.PathFilters) && ...
        r.NormalizeChannelOutputs==base.NormalizeChannelOutputs && ...
        r.NumTransmitAntennas==base.NumTransmitAntennas && ...
        r.NumReceiveAntennas==base.NumReceiveAntennas && ...
        r.AdditionalChannelExecutions==0 && ~r.ReceiverEstimatorInput, ...
        'sixgr:truth:IncompletePUSCHChannelReference', ...
        'No replacement, gap interpolation, different link, or channel re-execution is permitted.');
    losses(k)=10^(double(replays{k}.AppliedLargeScaleGain_dB)/20);
    assert(isfinite(losses(k)) && losses(k)>0, ...
        'sixgr:truth:MissingPUSCHReferenceLoss','Use each segment''s actual applied propagation loss.');
    gains{k}=r.PathGains.*losses(k); times{k}=r.SampleTimes_s; next=r.EndSampleExclusive;
end
gains=cat(1,gains{:}); times=vertcat(times{:});
assert(all(abs(diff(times)*prepared.SampleRateHz-1)<1e-6), ...
    'sixgr:truth:PUSCHReferenceClock','Every scored FFT sample needs its executed channel coefficient.');
op=snapshot.ReceiverChannelOperator; shape=double(snapshot.GridShape);
fs=double(prepared.SampleRateHz); ofdm=snapshot.ReceiverOFDMInfo;
carrier=snapshot.Carrier; nfft=double(ofdm.Nfft); L=shape(2);
assert(fs==op.SampleRateHz && fs==nfft*double(carrier.SubcarrierSpacing)*1000 && ...
    L==carrier.SymbolsPerSlot && shape(1)==12*carrier.NSizeGrid && ...
    prepared.Tx.Carrier.NSlot==carrier.NSlot, ...
    'sixgr:truth:PUSCHReferenceOFDMClock', ...
    'The executed native FFT clock must match; resampling requires its actual operator.');
aligned=prepared.ReceiveStartSample+op.AppliedTimingCorrection_samples;
offset=aligned-prepared.StartSample; start=prepared.StartSample-base.StartSample;
assert(start>=0 && start==fix(start) && offset>=0 && offset==fix(offset), ...
    'sixgr:truth:PUSCHReferenceTiming','Do not replace a missing TX origin or extrapolate negative FFT offsets.');
slotFirst=mod(double(carrier.NSlot),double(ofdm.SlotsPerSubframe))*L;
cp=double(ofdm.SymbolLengths(slotFirst+(1:L)))-nfft;
% Only receiver-retained DMRS resources are scored. A mixed TDD slot can
% reverse the physical link after its last DL pilot; later UL/guard samples
% have no executed DL channel and must neither be required nor invented.
indices=double(snapshot.PilotIndices(:));
assert(~isempty(indices) && all(isfinite(indices) & indices==fix(indices) & ...
    indices>=1 & indices<=prod(shape([1 2 4]))) && ...
    numel(unique(indices))==numel(indices), ...
    'sixgr:truth:DataReferencePilotResources','Retain every actual receiver DMRS resource exactly once.');
[~,pilotSymbols,~]=ind2sub(shape([1 2 4]),indices);
lastScoredSymbol=max(pilotSymbols);
absolute=(base.StartSample:next-1).';
phase=-2*pi/fs*(op.CaptureOriginCFOCorrection_Hz*(absolute-prepared.ReceiveStartSample)+ ...
    op.AlignedOriginCFOCorrection_Hz*(absolute-aligned));
assert(all(isfinite(phase)), 'sixgr:truth:PUSCHReferenceRXOperator','Applied RX phase operations must be finite.');
gains=gains.*reshape(exp(1i*phase),[],1,1,1);
h=sixgr.truth.receivedFFTChannelDiagonal(gains(start+1:end,:,:,:),base.PathFilters, ...
    nfft,cp(1:lastScoredSymbol),shape(1),offset,ofdm.CyclicPrefixFraction);
% Preserve full receiver-grid coordinates. Unscored symbols remain unknown,
% not an extrapolated physical channel, zero response, or receiver Hest.
full=complex(nan(shape(1),L,base.NumReceiveAntennas,base.NumTransmitAntennas,'like',h));
full(:,1:lastScoredSymbol,:,:)=h;
h=full;
% MatrixPorts is the actual layer-to-waveform map, including a hybrid
% element map if the transmitter executed one. The stream projection is
% applied exactly once afterward, as in queueData.
W=double(prepared.Tx.PrecodeInfo.MatrixPorts); projection=double(projection);
B=double(op.ReceiveCombiningMatrix);
assert(size(W,1)==size(prepared.Tx.Waveform,2) && size(W,2)==shape(4) && ...
    isequal(size(projection),[base.NumTransmitAntennas size(W,1)]) && ...
    isequal(size(B),[base.NumReceiveAntennas shape(3)]) && ...
    all(isfinite(W),'all') && all(isfinite(projection),'all') && all(isfinite(B),'all'), ...
    'sixgr:truth:PUSCHReferenceSpatialMap','Use the executed layer/waveform/element and receiver maps.');
amplitude=double(prepared.Tx.PowerContext.AmplitudeScale);
assert(isscalar(amplitude) && isfinite(amplitude) && amplitude>0, ...
    'sixgr:truth:MissingPUSCHReferencePower','Retain the single applied TX amplitude scale.');
normalization=1;
if base.NormalizeChannelOutputs, normalization=1/sqrt(base.NumReceiveAntennas); end
h=reshape(reshape(h,[],base.NumTransmitAntennas)*(projection*W), ...
    shape(1),L,base.NumReceiveAntennas,shape(4))*amplitude*normalization;
% Sample-space wave*conj(B) corresponds to B' multiplying a channel column.
h=permute(h,[1 2 4 3]);
h=reshape(reshape(h,[],base.NumReceiveAntennas)*conj(B),shape(1),L,shape(4),shape(3));
grid=permute(h,[1 2 4 3]);
evidence=struct('Source',"same_executed_channel_samples_and_actual_"+channel+"_linear_operators", ...
    'ReferencePlane',"nominal_linear_effective_"+channel+"_layer_channel_on_actual_receiver_FFT_clock", ...
    'AppliedChannelSource',base.Source,'RFImpairmentsIncluded',false, ...
    'ReceiverEstimatorInput',false,'GainOrPhaseFitted',false,'AdditionalChannelExecutions',0, ...
    'TimingOffsetRelativeTX_samples',offset,'TXAmplitudeScale',amplitude, ...
    'ChannelOutputNormalizationGain',normalization,'SegmentLossAmplitude',losses, ...
    'WaveformToElementMatrix',projection,'LayerToWaveformMatrix',W, ...
    'ReceiverChannelOperator',op,'ChannelReferenceSegmentCount',numel(captures), ...
    'ScoredPilotSymbolIndices0',unique(pilotSymbols).'-1, ...
    'ReferenceScope',"receiver_retained_DMRS_resources_only_later_symbols_unavailable");
end
