function decision=preparePUSCHULHARQReceiverDecision(harqOut)
% Prepare only the UL-SCH receiver-state decision at shared PUSCH completion.
% The coordinator separately validates the actual receive context/capture and
% independently decoded UCI. This helper neither supplies their authority nor
% converts an unattempted TB into a measured CRC failure. Public CRC remains
% unavailable; the reducer's internal CRCPass is a guarded logical boolean.
assert(isstruct(harqOut) && isscalar(harqOut) && ...
    all(isfield(harqOut,{'IndependentUCICompletionFlags','ReceiverHARQAttempt','CombinedDecodeOK'})), ...
    'sixgr:truth:MissingPUSCHULHARQCompletionEvidence', ...
    'Retain the actual receiver flags, receiver-state token and combined decode outcome.');
flags=harqOut.IndependentUCICompletionFlags;
assert(isstruct(flags) && isscalar(flags) && isfield(flags,'ULSCHDecodeAttempted') && ...
    islogical(flags.ULSCHDecodeAttempted) && isscalar(flags.ULSCHDecodeAttempted) && ...
    islogical(harqOut.CombinedDecodeOK) && isscalar(harqOut.CombinedDecodeOK) && ...
    (flags.ULSCHDecodeAttempted || ~harqOut.CombinedDecodeOK), ...
    'sixgr:truth:InvalidULHARQReceiverDecision', ...
    'Use actual logical decode flags; an unattempted TB cannot supply a CRC pass.');
soft=[];
if flags.ULSCHDecodeAttempted
    assert(isfield(harqOut,'SoftBuffer') && isstruct(harqOut.SoftBuffer) && ...
        isscalar(harqOut.SoftBuffer) && ~isempty(fieldnames(harqOut.SoftBuffer)), ...
        'sixgr:truth:ULHARQReceiverSoftEvidenceRequired', ...
        'Attempted decoding must retain its actual rate-recovered soft evidence.');
    soft=harqOut.SoftBuffer;
else
    % runULPUSCHThroughput deliberately omits new soft evidence when the
    % UL-SCH map/decode is unavailable. CombinedLLR may retain the old buffer;
    % never copy that value into a claim of a new received observation.
    for name=["SoftBuffer","HARQSoftBuffer"]
        assert(~isfield(harqOut,name) || isempty(harqOut.(name)), ...
            'sixgr:truth:UnattemptedULHARQSoftEvidence', ...
            'An unattempted TB cannot contribute a new soft buffer.');
    end
end
decision=struct('ReceiverAttempt',harqOut.ReceiverHARQAttempt, ...
    'DecodeAttempted',flags.ULSCHDecodeAttempted, ...
    'CRCPass',harqOut.CombinedDecodeOK,'SoftBuffer',soft);
end
