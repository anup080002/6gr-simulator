function contract = truthContract(llsCfg, trialTable)
%TRUTHCONTRACT Create and validate the explicit waveform-truth declaration.

if isempty(trialTable) || height(trialTable) == 0
    error("sixgr:lls:MissingTrialTruth", ...
        "A valid LLS result requires at least one executed transport-block trial.");
end
expectedLLRSource = "nr" + upper(string(llsCfg.simulation.link)) + "Decode_soft_llr";
requiredSources = all(trialTable.CRCSource == "decoded_transport_block_crc") && ...
    all(trialTable.LLRSource == expectedLLRSource) && ...
    all(trialTable.TrueChannelGridAvailable) && ...
    all(ismember(upper(trialTable.ChannelModel), ...
        ["AWGN","TDL-A","TDL-B","TDL-C","TDL-D","TDL-E", ...
         "CDL-A","CDL-B","CDL-C","CDL-D","CDL-E", ...
         "NTN-TDL-A","NTN-TDL-B","NTN-TDL-C","NTN-TDL-D", ...
         "NTN-CDL-A","NTN-CDL-B","NTN-CDL-C","NTN-CDL-D"]));
if ~requiredSources
    error("sixgr:lls:TruthContractViolation", ...
        "Trial provenance does not prove the required decoded waveform chain.");
end
resourceEvidence = all(trialTable.DataREPerLayer > 0) && ...
    all(trialTable.DMRSRE > 0) && all(trialTable.CodedBitsG > 0) && ...
    all(trialTable.FFTSize > 0) && all(trialTable.ModulationOrder > 0);
if ~resourceEvidence
    error("sixgr:lls:TruthContractViolation", ...
        "Executed trials are missing exact resource-grid/coded-bit/OFDM evidence.");
end
ldpcBackendEvidence = localLDPCBackendEvidence(llsCfg,trialTable);
if ~ldpcBackendEvidence
    error("sixgr:lls:LDPCBackendContractViolation", ...
        "Runtime LDPC backend does not match receiver.useMexLDPC authority.");
end
fixedAllocationEvidence = numel(unique(trialTable.TransportBlockSizeBits)) == 1 && ...
    numel(unique(trialTable.CodedBitsG)) == 1 && ...
    numel(unique(trialTable.TargetCodeRate)) == 1 && ...
    numel(unique(trialTable.ModulationOrder)) == 1 && ...
    numel(unique(trialTable.NumLayers)) == 1;
linkAdaptationEnabled = logical(sixgr.util.structGet(llsCfg,"linkAdaptation.enabled",false));
if ~fixedAllocationEvidence && ~linkAdaptationEnabled
    error("sixgr:lls:FixedMCSContractViolation", ...
        "Basic LLS curve changed TBS, G, code rate, modulation, or rank across the SNR sweep.");
end
linkAdaptationEvidence = localLinkAdaptationEvidence(llsCfg,trialTable);
if ~linkAdaptationEvidence
    error("sixgr:lls:LinkAdaptationTruthContractViolation", ...
        "Link adaptation must be causal and every selected MCS must match its decoded waveform trial.");
end
statisticalClass = string(llsCfg.simulation.statisticalClass);
harqEnabled = logical(sixgr.util.structGet(llsCfg,"harq.enabled",false));
harqEvidence = ~harqEnabled || localHARQEvidence(trialTable);
if ~harqEvidence
    error("sixgr:lls:HARQTruthContractViolation", ...
        "HARQ retransmissions must reuse packet identity and apply position-aware soft combining.");
end
interferenceEvidence = localInterferenceEvidence(llsCfg,trialTable);
if ~interferenceEvidence
    error("sixgr:lls:InterferenceTruthContractViolation", ...
        "Interference evidence must prove an independently encoded waveform/channel and calibrated D/I ratio.");
end
configuredPublicationBudget = statisticalClass == "publication_candidate" && ...
    double(llsCfg.simulation.minTransportBlocks) >= 1000 && ...
    double(llsCfg.simulation.minBlockErrors) >= 100 && ...
    double(llsCfg.simulation.maxTransportBlocks) >= double(llsCfg.simulation.minTransportBlocks) && ...
    lower(string(llsCfg.simulation.samplingPlan)) == "fixed_sample" && ...
    lower(string(llsCfg.simulation.confidenceIntervalMethod)) == ...
        "wilson_two_sided_fixed_sample";
executedStoppingRuleSatisfied = localExecutedStoppingRuleSatisfied(llsCfg,trialTable);
publicationEligible = configuredPublicationBudget && executedStoppingRuleSatisfied;
interferenceEnabled = logical(sixgr.util.structGet(llsCfg,"interference.enabled",false));
linkAdaptationEnabled = logical(sixgr.util.structGet(llsCfg,"linkAdaptation.enabled",false));
ntnEnabled = logical(sixgr.util.structGet(llsCfg,"ntn.enabled",false));
ntnEvidence = localNTNEvidence(llsCfg,trialTable);
if ~ntnEvidence
    error("sixgr:lls:NTNTruthContractViolation", ...
        "NTN truth requires exact configured geometry, Doppler, delay, profile, and runtime channel evidence.");
end
antennaEnabled = logical(sixgr.util.structGet(llsCfg,"antenna.enabled",false));
antennaEvidence = localAntennaEvidence(llsCfg,trialTable);
if ~antennaEvidence
    error("sixgr:lls:AntennaTruthContractViolation", ...
        "Antenna truth requires exact physical element counts, applied port-to-element weights, CDL coupling, and runtime array provenance.");
end
isacEnabled = logical(sixgr.util.structGet(llsCfg,"isac.enabled",false));
isacEvidence = localISACEvidence(llsCfg,trialTable);
if ~isacEvidence
    error("sixgr:lls:ISACTruthContractViolation", ...
        "ISAC truth requires the exact runtime PDSCH waveform, executed sensing channel, measured response, and configured target acceptance evidence.");
end
contract = table( ...
    string(llsCfg.scenario.id), ...
    true, true, true, true, true, true, true, true, true, true, true, true, ...
    true, true, true, true, harqEnabled, harqEvidence, ...
    true, interferenceEnabled, interferenceEvidence, ...
    linkAdaptationEnabled,linkAdaptationEvidence,ldpcBackendEvidence, ...
    ntnEnabled,ntnEvidence,antennaEnabled,antennaEvidence, ...
    isacEnabled,isacEvidence, ...
    false, false, false, false, ...
    statisticalClass, string(llsCfg.simulation.samplingPlan), ...
    string(llsCfg.simulation.confidenceIntervalMethod), ...
    configuredPublicationBudget,executedStoppingRuleSatisfied, ...
    publicationEligible, "valid_waveform_truth", ...
    'VariableNames', { ...
    'ScenarioId','WaveformGenerated','ActualLDPC','ActualRateMatching','ActualScrambling', ...
    'ActualModulation','ActualLayerMapping','ActualPrecoding','ActualResourceGrid','ActualOFDM', ...
    'ActualDMRS','ActualChannel','ActualNoise','ActualEqualization','ActualSoftDemapping', ...
    'ActualLDPCDecode','ActualCRC','ActualHARQ','HARQEvidenceValid', ...
    'HARQMetricSeparation','ActualInterference','InterferenceEvidenceValid', ...
    'ActualLinkAdaptation','LinkAdaptationEvidenceValid','ConfiguredLDPCBackendExecuted', ...
    'ActualNTNChannel','NTNEvidenceValid','ActualAntennaArray','AntennaEvidenceValid', ...
    'ActualISACSensing','ISACEvidenceValid', ...
    'UsesBLERLookupTable','UsesSyntheticBLER', ...
    'UsesRandomPassFailModel','UsesGeometryAsLLS','StatisticalClass', ...
    'SamplingPlan','ConfidenceIntervalMethod', ...
    'ConfiguredPublicationBudget','ExecutedStoppingRuleSatisfied', ...
    'PublicationEligible','Status'});
end

function valid = localISACEvidence(cfg,trials)
enabled = logical(sixgr.util.structGet(cfg,"isac.enabled",false));
required = ["ISACEnabled","ISACSensingExecuted","ISACEvidenceValid", ...
    "ISACObservationSource","ISACLogicalWaveformSHA256", ...
    "ISACDetectionCount","ISACMatchedTargetCount","ISACRangeRMSEM", ...
    "ISACAzimuthRMSEDeg"];
hasFields = all(ismember(required,string(trials.Properties.VariableNames)));
if ~enabled
    valid = ~hasFields || (~any(trials.ISACEnabled) && ...
        ~any(trials.ISACSensingExecuted));
    return;
end
if ~hasFields
    valid = false;
    return;
end
captured = trials.ISACSensingExecuted;
valid = all(trials.ISACEnabled) && nnz(captured) == 1 && ...
    all(trials.ISACEvidenceValid(captured)) && ...
    all(trials.ISACObservationSource(captured) == ...
        string(cfg.isac.processing.observationSource)) && ...
    all(strlength(trials.ISACLogicalWaveformSHA256(captured)) == 64) && ...
    all(trials.ISACDetectionCount(captured) >= ...
        trials.ISACMatchedTargetCount(captured)) && ...
    all(trials.ISACMatchedTargetCount(captured) >= ...
        double(cfg.isac.acceptance.minimumMatchedTargets)) && ...
    all(trials.ISACRangeRMSEM(captured) <= ...
        double(cfg.isac.acceptance.maximumRangeErrorM)) && ...
    all(trials.ISACAzimuthRMSEDeg(captured) <= ...
        double(cfg.isac.acceptance.maximumAzimuthErrorDeg));
end

function valid = localAntennaEvidence(cfg,trials)
required = ["AntennaEnabled","AntennaCouplingMode","AntennaTxRole", ...
    "AntennaRxRole","AntennaTxPhysicalElements", ...
    "AntennaRxPhysicalElements","AntennaTxLogicalPorts", ...
    "AntennaTxPortToElementSHA256","AntennaPatternSource", ...
    "AntennaPhysicalElementChannelApplied", ...
    "AntennaTransmitOrientationDeg","AntennaReceiveOrientationDeg"];
valid = all(ismember(required,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
enabled = logical(cfg.antenna.enabled);
if ~enabled
    valid = ~any(trials.AntennaEnabled) && ...
        ~any(trials.AntennaPhysicalElementChannelApplied) && ...
        all(trials.AntennaCouplingMode == "disabled");
    return;
end
state = sixgr.lls.resolveAntennaState(cfg);
valid = all(trials.AntennaEnabled) && ...
    all(trials.AntennaPhysicalElementChannelApplied) && ...
    all(trials.AntennaCouplingMode == state.CouplingMode) && ...
    all(trials.AntennaTxRole == state.TxRole) && ...
    all(trials.AntennaRxRole == state.RxRole) && ...
    all(trials.AntennaTxPhysicalElements == state.Tx.NumElements) && ...
    all(trials.AntennaRxPhysicalElements == state.Rx.NumElements) && ...
    all(trials.AntennaTxLogicalPorts == state.Tx.NumLogicalPorts) && ...
    all(trials.AntennaTxPortToElementSHA256 == state.Tx.PortToElementSHA256) && ...
    all(trials.AntennaPatternSource == state.Tx.PatternSource) && ...
    all(trials.NumRxAntennas == state.Rx.NumElements) && ...
    all(contains(trials.ChannelRealizationSource,"nrCDLChannel")) && ...
    all(startsWith(upper(trials.ChannelModel),"CDL-") | ...
        startsWith(upper(trials.ChannelModel),"NTN-CDL-"));
if ~valid
    return;
end
expected = localExpectedCDLOrientations(cfg);
valid = all(trials.AntennaTransmitOrientationDeg == ...
        string(mat2str(expected.Transmit))) && ...
    all(trials.AntennaReceiveOrientationDeg == ...
        string(mat2str(expected.Receive)));
end

function expected = localExpectedCDLOrientations(cfg)
channel = nrCDLChannel;
channel.DelayProfile = char(upper(string(cfg.channel.model)));
channel.CarrierFrequency = double(cfg.carrier.frequencyHz);
if startsWith(upper(string(cfg.channel.model)),"NTN-CDL-")
    channel.SatelliteElevationAngle = double(cfg.ntn.orbit.elevationAngleDeg);
end
channelInfo = info(channel);
expected = struct( ...
    "Transmit",[double(channelInfo.AnglesAoD(1)) ...
        double(channelInfo.AnglesZoD(1))-90 0], ...
    "Receive",[double(channelInfo.AnglesAoA(1)) ...
        double(channelInfo.AnglesZoA(1))-90 0]);
end

function valid = localNTNEvidence(cfg,trials)
required = ["NTNEnabled","NTNProfile","NTNOrbitType", ...
    "NTNPayloadArchitecture","NTNSlantRangeM", ...
    "NTNPropagationDelaySeconds","NTNPropagationDelaySamples", ...
    "NTNPropagationDelayCompensationMode", ...
    "NTNPhysicalSatelliteDopplerHz","NTNMobileMaximumDopplerHz", ...
    "NTNDopplerCompensationMode","NTNDopplerCompensationHz", ...
    "NTNResidualSatelliteDopplerHz","NTNSampleRateHz","NTNGeometrySource"];
valid = all(ismember(required,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
enabled = logical(cfg.ntn.enabled);
if ~enabled
    valid = ~any(trials.NTNEnabled) && all(trials.NTNSlantRangeM == 0) && ...
        all(trials.NTNPhysicalSatelliteDopplerHz == 0) && ...
        all(trials.NTNGeometrySource == "disabled");
    return;
end
sampleRates = unique(double(trials.NTNSampleRateHz));
if numel(sampleRates) ~= 1 || sampleRates <= 0
    valid = false;
    return;
end
expected = sixgr.lls.resolveNTNState(cfg,sampleRates);
tolerance = @(actual,target) abs(double(actual)-double(target)) <= ...
    128*eps(max(abs(double(target)),1));
valid = all(trials.NTNEnabled) && ...
    all(trials.NTNProfile == string(cfg.channel.model)) && ...
    all(trials.NTNOrbitType == string(cfg.ntn.orbit.type)) && ...
    all(trials.NTNPayloadArchitecture == string(cfg.ntn.payload.architecture)) && ...
    all(tolerance(trials.NTNSlantRangeM,expected.SlantRangeM)) && ...
    all(tolerance(trials.NTNPropagationDelaySeconds,expected.PropagationDelaySeconds)) && ...
    all(trials.NTNPropagationDelaySamples == expected.PropagationDelaySamples) && ...
    all(trials.NTNPropagationDelayCompensationMode == ...
        string(cfg.ntn.propagationDelay.compensationMode)) && ...
    all(tolerance(trials.NTNPhysicalSatelliteDopplerHz, ...
        expected.PhysicalSatelliteDopplerHz)) && ...
    all(tolerance(trials.NTNMobileMaximumDopplerHz,expected.MobileMaximumDopplerHz)) && ...
    all(trials.NTNDopplerCompensationMode == string(cfg.ntn.doppler.compensationMode)) && ...
    all(tolerance(trials.NTNDopplerCompensationHz,expected.DopplerCompensationHz)) && ...
    all(tolerance(trials.NTNResidualSatelliteDopplerHz, ...
        expected.ResidualSatelliteDopplerHz)) && ...
    all(trials.NTNGeometrySource == expected.GeometrySource) && ...
    all(contains(trials.ChannelRealizationSource,"NTN_profile"));
end

function valid = localLDPCBackendEvidence(cfg,trials)
required = ["UseMexLDPC","LDPCDecoderEngine"];
valid = all(ismember(required,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
configured = logical(cfg.receiver.useMexLDPC);
if configured
    valid = all(trials.UseMexLDPC) && ...
        all(contains(trials.LDPCDecoderEngine,"ldpc_decode_batch_kernel"));
else
    valid = ~any(trials.UseMexLDPC) && ...
        all(trials.LDPCDecoderEngine == "sixgr.phy.phycode.ldpcDecode");
end
end

function valid = localExecutedStoppingRuleSatisfied(cfg,trials)
indices = unique(double(trials.SNRIndex(:).'));
expected = 1:numel(double(cfg.simulation.snrDb));
valid = isequal(indices,expected);
if ~valid
    return;
end
study = lower(string(cfg.simulation.studyType));
for snrIndex = indices
    point = trials(trials.SNRIndex == snrIndex,:);
    if study == "harq_throughput"
        packetRows = point(point.AttemptIndex == 1,:);
        n = height(packetRows);
        if lower(string(cfg.harq.stoppingMetric)) == "post_harq_residual_bler"
            errors = sum(packetRows.FinalPacketCRCError);
        else
            errors = sum(packetRows.FirstTransmissionCRCError);
        end
    else
        n = height(point);
        errors = sum(point.CRCError);
    end
    decision = sixgr.lls.stats.evaluateSamplingPlan(cfg,errors,n);
    valid = logical(decision.Stop) && ...
        (string(cfg.simulation.statisticalClass) ~= "publication_candidate" || ...
        logical(decision.StatisticallyQualified));
    if ~valid
        return;
    end
end
end

function valid = localLinkAdaptationEvidence(cfg,trials)
enabled = logical(sixgr.util.structGet(cfg,"linkAdaptation.enabled",false));
required = ["LinkAdaptationEnabled","LinkAdaptationDecisionSource", ...
    "LinkAdaptationFeedbackTrialIndex","LinkAdaptationFeedbackSINRdB", ...
    "LinkAdaptationSelectedCQI","LinkAdaptationSelectedMCSIndex", ...
    "LinkAdaptationThresholdSource","LinkAdaptationThresholdValueRole", ...
    "LinkAdaptationThresholdCalibrationId","MCSIndex","MCSTable","Modulation"];
if ~enabled
    valid = ~ismember("LinkAdaptationEnabled",string(trials.Properties.VariableNames)) || ...
        ~any(trials.LinkAdaptationEnabled);
    return;
end
valid = all(ismember(required,string(trials.Properties.VariableNames))) && ...
    all(trials.LinkAdaptationEnabled) && ...
    trials.LinkAdaptationDecisionSource(1) == "configured_bootstrap_mcs" && ...
    trials.LinkAdaptationFeedbackTrialIndex(1) == 0 && ...
    all(trials.LinkAdaptationDecisionSource(2:end) == ...
        "previous_trial_receiver_post_equalization_sinr") && ...
    all(trials.LinkAdaptationFeedbackTrialIndex(2:end) == trials.TrialIndex(1:end-1)) && ...
    all(trials.LinkAdaptationSelectedMCSIndex == trials.MCSIndex) && ...
    all(strlength(trials.LinkAdaptationThresholdSource) > 0) && ...
    all(strlength(trials.LinkAdaptationThresholdCalibrationId) > 0);
if ~valid
    return;
end
for index = 1:height(trials)
    profile = sixgr.link.resolveMCSProfile(trials.MCSTable(index),trials.MCSIndex(index));
    valid = profile.Valid && strcmpi(string(profile.Modulation),trials.Modulation(index)) && ...
        abs(double(profile.TargetCodeRate)-double(trials.TargetCodeRate(index))) <= 1e-12;
    if ~valid
        return;
    end
end
end

function valid = localInterferenceEvidence(cfg,trials)
required = ["InterferenceEnabled","InterfererWaveformCount","ConfiguredDIRdB", ...
    "MeasuredDIRdB","MeasuredPreEqualizationSINRdB","InterferenceSource"];
valid = all(ismember(required,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
enabled = logical(sixgr.util.structGet(cfg,"interference.enabled",false));
if enabled
    valid = all(trials.InterferenceEnabled) && ...
        all(trials.InterfererWaveformCount == 1) && ...
        all(trials.InterferenceSource == "independent_transport_block_waveform_and_channel") && ...
        all(isfinite(trials.ConfiguredDIRdB)) && all(isfinite(trials.MeasuredDIRdB)) && ...
        all(isfinite(trials.MeasuredPreEqualizationSINRdB)) && ...
        all(abs(trials.MeasuredDIRdB-trials.ConfiguredDIRdB) <= 0.05);
else
    valid = ~any(trials.InterferenceEnabled) && ...
        all(trials.InterfererWaveformCount == 0) && ...
        all(trials.InterferenceSource == "disabled");
end
end

function valid = localHARQEvidence(trials)
required = ["PacketIndex","AttemptIndex","IsRetransmission", ...
    "RV","HARQSoftCombiningApplied","FirstTransmissionCRCError", ...
    "FinalPacketCRCError","PacketTransmissions"];
valid = all(ismember(required,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
retransmissions = trials.AttemptIndex > 1;
valid = all(trials.IsRetransmission == retransmissions) && ...
    all(trials.HARQSoftCombiningApplied(retransmissions)) && ...
    all(trials.RV >= 0 & trials.RV <= 3) && ...
    all(trials.PacketTransmissions >= trials.AttemptIndex);
end
