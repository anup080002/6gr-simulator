function [rxWaveform, trueChannelGrid, channelInfo] = applyChannel(txWaveform, carrier, llsCfg, channelSeed)
%APPLYCHANNEL Apply one independent waveform channel realization.
%
% AWGN uses an explicit unit channel.  TDL/CDL paths use the corresponding
% 5G Toolbox stochastic waveform filter and derive the exact per-RE true
% channel from the same path gains and filters.  No scalar channel is
% expanded across a fading resource grid.

model = upper(string(llsCfg.channel.model));
ntnEnabled = logical(sixgr.util.structGet(llsCfg, "ntn.enabled", false));
isNTNTDL = startsWith(model, "NTN-TDL-");
isNTNCDL = startsWith(model, "NTN-CDL-");
if ntnEnabled ~= (isNTNTDL || isNTNCDL)
    error("sixgr:lls:NTNEnableProfileMismatch", ...
        "ntn.enabled and channel.model must agree: enabled NTN requires an " + ...
        "NTN-TDL-* or NTN-CDL-* profile, and those profiles require ntn.enabled=true.");
end
linkDirection = upper(string(llsCfg.simulation.link));
if linkDirection == "PDSCH"
    transmissionDirection = "Downlink";
elseif linkDirection == "PUSCH"
    transmissionDirection = "Uplink";
else
    error("sixgr:lls:InvalidLinkDirection", ...
        "Waveform channel direction requires simulation.link=PDSCH or PUSCH.");
end
antennaState = sixgr.lls.resolveAntennaState(llsCfg);
if model == "AWGN"
    rxWaveform = txWaveform;
    trueChannelGrid = complex(ones(carrier.NSizeGrid*12, carrier.SymbolsPerSlot, 1, 1, "like", txWaveform));
    channelInfo = struct( ...
        "Model", "AWGN", ...
        "Source", "explicit_unit_flat_channel", ...
        "PathGainsAvailable", false, ...
        "TrueChannelGridAvailable", true, ...
        "TimingOffsetSamples", 0, ...
        "MaximumDopplerHz", 0, ...
        "NTNEnabled", false, ...
        "NTNProfile", "", ...
        "NTNOrbitType", "", ...
        "NTNPayloadArchitecture", "", ...
        "NTNSlantRangeM", 0, ...
        "NTNPropagationDelaySeconds", 0, ...
        "NTNPropagationDelaySamples", 0, ...
        "NTNPropagationDelayCompensationMode", "disabled", ...
        "NTNPhysicalSatelliteDopplerHz", 0, ...
        "NTNMobileMaximumDopplerHz", 0, ...
        "NTNDopplerCompensationMode", "none", ...
        "NTNDopplerCompensationHz", 0, ...
        "NTNResidualSatelliteDopplerHz", 0, ...
        "NTNSampleRateHz", 0, ...
        "NTNGeometrySource", "disabled", ...
        "AntennaEnabled", false, ...
        "AntennaCouplingMode", "disabled", ...
        "AntennaTxRole", "", ...
        "AntennaRxRole", "", ...
        "AntennaTxPhysicalElements", 1, ...
        "AntennaRxPhysicalElements", 1, ...
        "AntennaTxLogicalPorts", size(txWaveform,2), ...
        "AntennaTxPortToElementSHA256", "disabled", ...
        "AntennaPatternSource", "disabled", ...
        "AntennaPhysicalElementChannelApplied", false, ...
        "AntennaTransmitOrientationDeg", [0 0 0], ...
        "AntennaReceiveOrientationDeg", [0 0 0], ...
        "TransmissionDirection", transmissionDirection, ...
        "ChannelSeed", double(channelSeed));
    return;
end

if startsWith(model, "TDL-") || isNTNTDL
    if exist("nrTDLChannel", "class") ~= 8 && exist("nrTDLChannel", "file") ~= 2
        error("sixgr:lls:MissingTDLChannel", "nrTDLChannel is required for %s.", model);
    end
    channel = nrTDLChannel;
    channel.DelayProfile = char(model);
    channel.NumTransmitAntennas = double(llsCfg.channel.txAntennas);
    channel.NumReceiveAntennas = double(llsCfg.channel.rxAntennas);
    try
        channel.TransmissionDirection = char(transmissionDirection);
    catch
    end
elseif startsWith(model, "CDL-") || isNTNCDL
    if exist("nrCDLChannel", "class") ~= 8 && exist("nrCDLChannel", "file") ~= 2
        error("sixgr:lls:MissingCDLChannel", "nrCDLChannel is required for %s.", model);
    end
    channel = nrCDLChannel;
    channel.DelayProfile = char(model);
    channel.CarrierFrequency = double(llsCfg.carrier.frequencyHz);
    if antennaState.Enabled
        channel.TransmitAntennaArray = localCDLArray( ...
            channel.TransmitAntennaArray,antennaState.Tx.ChannelArray, ...
            "antenna." + antennaState.TxRole);
        channel.ReceiveAntennaArray = localCDLArray( ...
            channel.ReceiveAntennaArray,antennaState.Rx.ChannelArray, ...
            "antenna." + antennaState.RxRole);
    else
        channel.TransmitAntennaArray = localCDLArray( ...
            channel.TransmitAntennaArray,llsCfg.channel.cdl.transmitArray, ...
            "channel.cdl.transmitArray");
        channel.ReceiveAntennaArray = localCDLArray( ...
            channel.ReceiveAntennaArray,llsCfg.channel.cdl.receiveArray, ...
            "channel.cdl.receiveArray");
    end
else
    error("sixgr:lls:UnsupportedChannel", "Unsupported waveform channel model %s.", model);
end

ofdm = nrOFDMInfo(carrier);
channel.SampleRate = double(ofdm.SampleRate);
channel.DelaySpread = double(llsCfg.channel.delaySpreadSeconds);
ntnState = sixgr.lls.resolveNTNState(llsCfg, double(ofdm.SampleRate));
speedMps = double(llsCfg.channel.velocityKmph) / 3.6;
mobileDopplerHz = speedMps * double(llsCfg.carrier.frequencyHz) / 299792458;
if ntnState.Enabled
    mobileDopplerHz = ntnState.MobileMaximumDopplerHz;
end
if isNTNTDL
    channel.MIMOCorrelation = char(string(llsCfg.ntn.tdl.mimoCorrelation));
    channel.Polarization = char(string(llsCfg.ntn.tdl.polarization));
    channel.MaximumDopplerShift = mobileDopplerHz;
    channel.SatelliteDopplerShift = ntnState.ResidualSatelliteDopplerHz;
elseif isNTNCDL
    channel.SatelliteElevationAngle = ntnState.ElevationAngleDeg;
    channel.MaximumDopplerShift = [mobileDopplerHz ntnState.ResidualSatelliteDopplerHz];
    directionAzimuthDeg = double(llsCfg.ntn.doppler.mobileDirectionAzimuthDeg);
    directionZenithDeg = double(llsCfg.ntn.doppler.mobileDirectionZenithDeg);
    preInfo = info(channel);
    departureAzimuthDeg = double(preInfo.AnglesAoD(1));
    departureZenithDeg = double(preInfo.AnglesZoD(1));
    channel.UTDirectionOfTravel = [directionAzimuthDeg departureAzimuthDeg; ...
        directionZenithDeg departureZenithDeg];
    if ~antennaState.Enabled && logical(llsCfg.ntn.cdl.autoOrientSatelliteArray)
        channel.TransmitArrayOrientation = ...
            [departureAzimuthDeg; departureZenithDeg-90; 0];
    end
else
    channel.MaximumDopplerShift = mobileDopplerHz;
end
if antennaState.Enabled && ...
        strcmpi(string(antennaState.PointingMode),"auto_first_path_boresight")
    preInfo = info(channel);
    departureAzimuthDeg = double(preInfo.AnglesAoD(1));
    departureZenithDeg = double(preInfo.AnglesZoD(1));
    arrivalAzimuthDeg = double(preInfo.AnglesAoA(1));
    arrivalZenithDeg = double(preInfo.AnglesZoA(1));
    channel.TransmitArrayOrientation = ...
        [departureAzimuthDeg; departureZenithDeg-90; 0];
    channel.ReceiveArrayOrientation = ...
        [arrivalAzimuthDeg; arrivalZenithDeg-90; 0];
end
maximumDopplerHz = max(abs([mobileDopplerHz ...
    ntnState.ResidualSatelliteDopplerHz]));
if isprop(channel, "RandomStream")
    channel.RandomStream = "mt19937ar with seed";
end
if isprop(channel, "Seed")
    channel.Seed = double(channelSeed);
end
if isprop(channel, "NormalizePathGains")
    channel.NormalizePathGains = true;
end
if isprop(channel, "NormalizeChannelOutputs")
    channel.NormalizeChannelOutputs = true;
end
reset(channel);
cleanup = onCleanup(@() release(channel)); %#ok<NASGU>
objectInfo = info(channel);
maximumDelay = max(0, round(double(sixgr.util.structGet(objectInfo, "MaximumChannelDelay", 0))));
propagationDelaySamples = double(ntnState.PropagationDelaySamples);
if propagationDelaySamples > 0 && ...
        ~strcmpi(string(ntnState.PropagationDelayCompensationMode), ...
        "perfect_geometry_timing_advance")
    error("sixgr:lls:UnsupportedNTNDelayCompensation", ...
        "The compact slot LLS requires " + ...
        "ntn.propagationDelay.compensationMode=perfect_geometry_timing_advance " + ...
        "when propagation delay is enabled.");
end
channelInputWaveform = txWaveform;
if antennaState.Enabled
    expectedLogicalPorts = double(antennaState.Tx.NumLogicalPorts);
    if size(txWaveform,2) ~= expectedLogicalPorts
        error("sixgr:lls:AntennaWaveformPortMismatch", ...
            "The logical waveform has %d column(s), but antenna.%s binds %d logical port(s).", ...
            size(txWaveform,2),antennaState.TxRole,expectedLogicalPorts);
    end
    channelInputWaveform = txWaveform * transpose(antennaState.Tx.PortToElementMatrix);
    if size(channelInputWaveform,2) ~= double(antennaState.Tx.NumElements)
        error("sixgr:lls:AntennaElementProjectionMismatch", ...
            "The antenna projection produced %d columns instead of %d physical elements.", ...
            size(channelInputWaveform,2),antennaState.Tx.NumElements);
    end
    inputPower = sum(mean(abs(txWaveform).^2,1));
    projectedPower = sum(mean(abs(channelInputWaveform).^2,1));
    relativePowerError = abs(projectedPower-inputPower) / max(inputPower,eps);
    if ~(isfinite(relativePowerError) && relativePowerError <= 1e-12)
        error("sixgr:lls:AntennaProjectionPowerMismatch", ...
            "Logical-to-element waveform projection changed total power by relative error %.17g.", ...
            relativePowerError);
    end
end
padded = [channelInputWaveform; complex(zeros(maximumDelay, size(channelInputWaveform,2), ...
    "like", txWaveform))];
[channelWaveform, pathGains, sampleTimes] = channel(padded);
% The satellite slant-range delay is a bulk propagation shift, not part of
% the finite multipath impulse response. Apply it explicitly after the
% stochastic NTN channel and remove it through the configured ideal timing
% advance. nrPerfectChannelEstimate must receive only the excess multipath
% timing offset accepted by its channel-filter model.
rawWaveform = [complex(zeros(propagationDelaySamples, ...
    size(channelWaveform,2),"like",channelWaveform)); channelWaveform];
pathFilters = getPathFilters(channel);
[excessTimingOffset, timingMagnitude] = nrPerfectTimingEstimate(pathGains, pathFilters);
excessTimingOffset = max(0, round(double(excessTimingOffset)));
timingOffset = propagationDelaySamples + excessTimingOffset;
first = timingOffset + 1;
last = first + size(txWaveform,1) - 1;
if last > size(rawWaveform,1)
    rawWaveform(end+1:last,:) = complex(0); %#ok<AGROW>
end
rxWaveform = rawWaveform(first:last,:);
trueChannelGrid = nrPerfectChannelEstimate( ...
    carrier, pathGains, pathFilters, excessTimingOffset, sampleTimes);
if antennaState.Enabled
    trueChannelGrid = localProjectTrueChannelToLogicalPorts( ...
        trueChannelGrid,antennaState.Tx.PortToElementMatrix);
end
expectedSize = [carrier.NSizeGrid*12 carrier.SymbolsPerSlot];
if size(trueChannelGrid,1) ~= expectedSize(1) || size(trueChannelGrid,2) ~= expectedSize(2)
    error("sixgr:lls:InvalidPerfectChannelGrid", ...
        "Perfect fading channel grid has size %s; expected first dimensions [%d %d].", ...
        mat2str(size(trueChannelGrid)), expectedSize(1), expectedSize(2));
end
if any(~isfinite(trueChannelGrid), "all")
    error("sixgr:lls:InvalidPerfectChannelGrid", ...
        "Perfect fading channel grid contains nonfinite values.");
end
channelInfo = struct( ...
    "Model", model, ...
    "Source", localChannelSource(model), ...
    "PathGainsAvailable", ~isempty(pathGains), ...
    "TrueChannelGridAvailable", true, ...
    "TrueChannelGridSize", double(size(trueChannelGrid)), ...
    "TrueChannelGridVariance", double(var(abs(trueChannelGrid(:)))), ...
    "TimingOffsetSamples", timingOffset, ...
    "TimingMagnitude", double(timingMagnitude), ...
    "MaximumChannelDelaySamples", maximumDelay, ...
    "MaximumDopplerHz", maximumDopplerHz, ...
    "NTNEnabled", logical(ntnState.Enabled), ...
    "NTNProfile", string(ntnState.Profile), ...
    "NTNOrbitType", string(ntnState.OrbitType), ...
    "NTNPayloadArchitecture", string(ntnState.PayloadArchitecture), ...
    "NTNSlantRangeM", double(ntnState.SlantRangeM), ...
    "NTNPropagationDelaySeconds", double(ntnState.PropagationDelaySeconds), ...
    "NTNPropagationDelaySamples", propagationDelaySamples, ...
    "NTNPropagationDelayCompensationMode", ...
        string(ntnState.PropagationDelayCompensationMode), ...
    "NTNPhysicalSatelliteDopplerHz", ...
        double(ntnState.PhysicalSatelliteDopplerHz), ...
    "NTNMobileMaximumDopplerHz", double(ntnState.MobileMaximumDopplerHz), ...
    "NTNDopplerCompensationMode", string(ntnState.DopplerCompensationMode), ...
    "NTNDopplerCompensationHz", double(ntnState.DopplerCompensationHz), ...
    "NTNResidualSatelliteDopplerHz", ...
        double(ntnState.ResidualSatelliteDopplerHz), ...
    "NTNSampleRateHz", double(ofdm.SampleRate), ...
    "NTNGeometrySource", string(ntnState.GeometrySource), ...
    "AntennaEnabled", logical(antennaState.Enabled), ...
    "AntennaCouplingMode", string(antennaState.CouplingMode), ...
    "AntennaTxRole", string(antennaState.TxRole), ...
    "AntennaRxRole", string(antennaState.RxRole), ...
    "AntennaTxPhysicalElements", localAntennaValue(antennaState,"Tx.NumElements",size(channelInputWaveform,2)), ...
    "AntennaRxPhysicalElements", localAntennaValue(antennaState,"Rx.NumElements",size(rxWaveform,2)), ...
    "AntennaTxLogicalPorts", size(txWaveform,2), ...
    "AntennaTxPortToElementSHA256", localAntennaText(antennaState,"Tx.PortToElementSHA256","disabled"), ...
    "AntennaPatternSource", localAntennaText(antennaState,"Tx.PatternSource","disabled"), ...
    "AntennaPhysicalElementChannelApplied", logical(antennaState.Enabled), ...
    "AntennaTransmitOrientationDeg", localChannelOrientation(channel,"TransmitArrayOrientation"), ...
    "AntennaReceiveOrientationDeg", localChannelOrientation(channel,"ReceiveArrayOrientation"), ...
    "TransmissionDirection", transmissionDirection, ...
    "SampleRateHz", double(ofdm.SampleRate), ...
    "ChannelSeed", double(channelSeed), ...
    "NormalizePathGains", true, ...
    "NormalizeChannelOutputs", true);
end

function projected = localProjectTrueChannelToLogicalPorts(physical,weights)
% physical is K-by-L-by-NRx-by-NTx and weights is NTx-by-Nport.
if size(physical,4) ~= size(weights,1)
    error("sixgr:lls:AntennaTrueChannelDimensionMismatch", ...
        "Physical true-channel TX dimension %d does not match %d antenna weights.", ...
        size(physical,4),size(weights,1));
end
projected = complex(zeros(size(physical,1),size(physical,2), ...
    size(physical,3),size(weights,2),"like",physical));
for port = 1:size(weights,2)
    coefficients = reshape(weights(:,port),1,1,1,[]);
    projected(:,:,:,port) = sum(physical .* coefficients,4);
end
end

function value = localAntennaValue(state,path,disabledValue)
if state.Enabled
    value = double(sixgr.util.structGet(state,path,NaN));
else
    value = double(disabledValue);
end
end

function value = localAntennaText(state,path,disabledValue)
if state.Enabled
    value = string(sixgr.util.structGet(state,path,""));
else
    value = string(disabledValue);
end
end

function value = localChannelOrientation(channel,propertyName)
if isprop(channel,propertyName)
    raw = channel.(propertyName);
    value = double(raw(:).');
else
    value = [0 0 0];
end
end

function source = localChannelSource(model)
if startsWith(model,"NTN-TDL-")
    source = "nrTDLChannel_NTN_profile_path_gains_and_nrPerfectChannelEstimate";
elseif startsWith(model,"NTN-CDL-")
    source = "nrCDLChannel_NTN_profile_path_gains_and_nrPerfectChannelEstimate";
elseif startsWith(model,"TDL-")
    source = "nrTDLChannel_path_gains_and_nrPerfectChannelEstimate";
else
    source = "nrCDLChannel_path_gains_and_nrPerfectChannelEstimate";
end
end

function array = localCDLArray(array,configured,path)
% Bind every 38.901 array degree of freedom from the immutable LLS YAML.
% In particular, do not collapse multi-port CDL links into an artificial
% single-polarized column merely because the requested port count is N.
required = ["size","elementSpacingWavelength","polarizationAnglesDeg", ...
    "orientationDeg","element","polarizationModel"];
for index = 1:numel(required)
    if ~isfield(configured,required(index))
        error("sixgr:lls:MissingCDLArrayConfiguration", ...
            "%s.%s is required for an executable CDL array.",path,required(index));
    end
end
array.Size = double(configured.size(:).');
array.ElementSpacing = double(configured.elementSpacingWavelength(:).');
array.PolarizationAngles = double(configured.polarizationAnglesDeg(:).');
array.Orientation = double(configured.orientationDeg(:));
array.Element = char(string(configured.element));
array.PolarizationModel = char(string(configured.polarizationModel));
end
