function summary = buildLinkAdaptationOperatingPointSummary(cfg, pointSummary, trials)
%BUILDLINKADAPTATIONOPERATINGPOINTSUMMARY Aggregate causal AMC/OLLA evidence.
%   Every value is reduced from persisted-equivalent waveform trial rows;
%   no configured SINR, BLER model, or lookup result substitutes a receiver
%   measurement or decoded CRC outcome.

arguments
    cfg (1,1) struct
    pointSummary table
    trials table
end

if ~logical(sixgr.util.structGet(cfg, "linkAdaptation.enabled", false))
    summary = table();
    return;
end
required = ["SNRIndex","TrialIndex","CRCError","MCSIndex", ...
    "PostEqSINRdB","LinkAdaptationFeedbackDelaySlots", ...
    "LinkAdaptationFeedbackAgeSlots","LinkAdaptationSelectedCQI", ...
    "LinkAdaptationSchedulingEligible","LinkAdaptationForcedWaveformProbe", ...
    "OLLAOffsetDbApplied","OLLAFeedbackACK","OLLAUpdateCount"];
missing = setdiff(required, string(trials.Properties.VariableNames));
if ~isempty(missing)
    error("sixgr:lls:LinkAdaptationSummarySchemaMissing", ...
        "Link-adaptation summary is missing runtime columns: %s", ...
        char(strjoin(missing, ", ")));
end

indices = unique(double(trials.SNRIndex(:)), "sorted");
rows = repmat(localEmptyRow(), numel(indices), 1);
targetBLER = double(cfg.linkAdaptation.olla.targetBLER);
minMCS = double(cfg.linkAdaptation.minimumMCSIndex);
maxMCS = double(cfg.linkAdaptation.maximumMCSIndex);
confidence = double(cfg.simulation.confidenceLevel);
for k = 1:numel(indices)
    snrIndex = indices(k);
    T = trials(double(trials.SNRIndex) == snrIndex, :);
    [~, order] = sort(double(T.TrialIndex));
    T = T(order,:);
    delayValues = unique(double(T.LinkAdaptationFeedbackDelaySlots));
    if numel(delayValues) ~= 1 || ~isfinite(delayValues) || delayValues < 1
        error("sixgr:lls:LinkAdaptationSummaryDelayMismatch", ...
            "SNR index %d does not have one finite causal feedback delay.", snrIndex);
    end
    delay = double(delayValues);
    evaluationMask = double(T.TrialIndex) > delay;
    feedbackMask = evaluationMask & ...
        isfinite(double(T.LinkAdaptationFeedbackAgeSlots));
    if any(double(T.LinkAdaptationFeedbackAgeSlots(feedbackMask)) ~= delay)
        error("sixgr:lls:LinkAdaptationSummaryCausalityMismatch", ...
            "SNR index %d contains feedback with the wrong age.", snrIndex);
    end
    errors = nnz(logical(T.CRCError));
    evalTrials = nnz(evaluationMask);
    evalErrors = nnz(logical(T.CRCError(evaluationMask)));
    if evalTrials > 0
        evalBLER = evalErrors / evalTrials;
        [evalLower, evalUpper] = sixgr.lls.stats.wilsonInterval( ...
            evalErrors, evalTrials, confidence);
    else
        evalBLER = NaN;
        evalLower = NaN;
        evalUpper = NaN;
    end
    mcs = double(T.MCSIndex);
    cqi = double(T.LinkAdaptationSelectedCQI);
    feedbackSINR = double(T.PostEqSINRdB(feedbackMask));
    olla = double(T.OLLAOffsetDbApplied);
    ack = double(T.OLLAFeedbackACK);
    point = localPointRow(pointSummary, snrIndex);
    lowerSaturated = any(evaluationMask) && all(mcs(evaluationMask) <= minMCS);
    upperSaturated = any(evaluationMask) && all(mcs(evaluationMask) >= maxMCS);
    classification = localTrackingClassification( ...
        evalBLER, evalLower, evalUpper, targetBLER, ...
        lowerSaturated, upperSaturated, evalTrials);
    rows(k) = struct( ...
        "ScenarioId", string(cfg.scenario.id), ...
        "Link", upper(string(cfg.simulation.link)), ...
        "SNRIndex", double(snrIndex), ...
        "SNRdB", double(localValue(point, "SNRdB", NaN)), ...
        "RuntimeTrials", double(height(T)), ...
        "RuntimeBlockErrors", double(errors), ...
        "RuntimeBLER", double(errors / height(T)), ...
        "RuntimeBLERLowerCI", double(localValue(point, "BLERLowerCI", NaN)), ...
        "RuntimeBLERUpperCI", double(localValue(point, "BLERUpperCI", NaN)), ...
        "ThroughputBps", double(localValue(point, "ThroughputBps", NaN)), ...
        "FeedbackDelaySlots", delay, ...
        "BootstrapTrials", double(nnz(~evaluationMask)), ...
        "PostDelayEvaluationTrials", double(evalTrials), ...
        "PostDelayBlockErrors", double(evalErrors), ...
        "PostDelayBLER", double(evalBLER), ...
        "PostDelayBLERLowerCI", double(evalLower), ...
        "PostDelayBLERUpperCI", double(evalUpper), ...
        "TargetBLER", targetBLER, ...
        "TargetTrackingClassification", string(classification), ...
        "LowerMCSSaturated", logical(lowerSaturated), ...
        "UpperMCSSaturated", logical(upperSaturated), ...
        "MinimumMCSIndex", localFiniteMin(mcs), ...
        "MaximumMCSIndex", localFiniteMax(mcs), ...
        "MeanMCSIndex", localFiniteMean(mcs), ...
        "MCSChangeCount", double(nnz(diff(mcs) ~= 0)), ...
        "MinimumCQI", localFiniteMin(cqi), ...
        "MaximumCQI", localFiniteMax(cqi), ...
        "MeanCQI", localFiniteMean(cqi), ...
        "MeanFeedbackPostEqSINRdB", localFiniteMean(feedbackSINR), ...
        "MinimumFeedbackPostEqSINRdB", localFiniteMin(feedbackSINR), ...
        "MaximumFeedbackPostEqSINRdB", localFiniteMax(feedbackSINR), ...
        "SchedulerEligibleTrials", double(nnz(logical(T.LinkAdaptationSchedulingEligible))), ...
        "DiagnosticWaveformProbeTrials", double(nnz(logical(T.LinkAdaptationForcedWaveformProbe))), ...
        "ILLAFeedbackAppliedTrials", double(nnz(feedbackMask)), ...
        "OLLAACKCount", double(nnz(ack == 1)), ...
        "OLLANACKCount", double(nnz(ack == 0)), ...
        "OLLAInitialOffsetDb", double(olla(1)), ...
        "OLLAFinalOffsetDb", double(olla(end)), ...
        "OLLAMinimumOffsetDb", localFiniteMin(olla), ...
        "OLLAMaximumOffsetDb", localFiniteMax(olla), ...
        "OLLAUpdateCount", localFiniteMax(double(T.OLLAUpdateCount)), ...
        "StatisticalClass", string(cfg.simulation.statisticalClass), ...
        "PublicationEligible", logical(localValue(point, "StatisticalPointQualified", false) && ...
            string(cfg.simulation.statisticalClass) == "publication_candidate"), ...
        "ExecutionBackend", "waveform_truth", ...
        "ApproximationMode", "none", ...
        "ValueRole", "runtime_receiver_cqi_illa_and_decoded_crc_olla_reduction");
end
summary = struct2table(rows);
end

function row = localEmptyRow()
row = struct( ...
    "ScenarioId", "", "Link", "", "SNRIndex", NaN, "SNRdB", NaN, ...
    "RuntimeTrials", 0, "RuntimeBlockErrors", 0, "RuntimeBLER", NaN, ...
    "RuntimeBLERLowerCI", NaN, "RuntimeBLERUpperCI", NaN, ...
    "ThroughputBps", NaN, "FeedbackDelaySlots", NaN, ...
    "BootstrapTrials", 0, "PostDelayEvaluationTrials", 0, ...
    "PostDelayBlockErrors", 0, "PostDelayBLER", NaN, ...
    "PostDelayBLERLowerCI", NaN, "PostDelayBLERUpperCI", NaN, ...
    "TargetBLER", NaN, "TargetTrackingClassification", "", ...
    "LowerMCSSaturated", false, "UpperMCSSaturated", false, ...
    "MinimumMCSIndex", NaN, "MaximumMCSIndex", NaN, ...
    "MeanMCSIndex", NaN, "MCSChangeCount", 0, ...
    "MinimumCQI", NaN, "MaximumCQI", NaN, "MeanCQI", NaN, ...
    "MeanFeedbackPostEqSINRdB", NaN, ...
    "MinimumFeedbackPostEqSINRdB", NaN, ...
    "MaximumFeedbackPostEqSINRdB", NaN, ...
    "SchedulerEligibleTrials", 0, "DiagnosticWaveformProbeTrials", 0, ...
    "ILLAFeedbackAppliedTrials", 0, "OLLAACKCount", 0, "OLLANACKCount", 0, ...
    "OLLAInitialOffsetDb", NaN, "OLLAFinalOffsetDb", NaN, ...
    "OLLAMinimumOffsetDb", NaN, "OLLAMaximumOffsetDb", NaN, ...
    "OLLAUpdateCount", 0, "StatisticalClass", "", ...
    "PublicationEligible", false, "ExecutionBackend", "", ...
    "ApproximationMode", "", "ValueRole", "");
end

function point = localPointRow(summary, index)
mask = double(summary.SNRIndex) == double(index);
if nnz(mask) ~= 1
    error("sixgr:lls:LinkAdaptationSummaryPointMismatch", ...
        "Expected exactly one point-summary row for SNR index %d.", index);
end
point = summary(mask,:);
end

function value = localValue(row, name, fallback)
if ismember(name, string(row.Properties.VariableNames))
    value = row.(char(name))(1);
else
    value = fallback;
end
end

function value = localFiniteMean(values)
values = double(values(:));
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = mean(values); end
end

function value = localFiniteMin(values)
values = double(values(:));
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = min(values); end
end

function value = localFiniteMax(values)
values = double(values(:));
values = values(isfinite(values));
if isempty(values), value = NaN; else, value = max(values); end
end

function value = localTrackingClassification(bler, lower, upper, target, lowerSat, upperSat, count)
if count < 1
    value = "no_post_delay_evaluation_trials";
elseif lowerSat && bler > target
    value = "coverage_limited_at_minimum_mcs";
elseif upperSat && bler < target
    value = "capacity_limited_at_maximum_mcs";
elseif isfinite(lower) && isfinite(upper) && lower <= target && target <= upper
    value = "target_within_observed_confidence_interval";
elseif bler > target
    value = "observed_bler_above_target_not_saturated";
else
    value = "observed_bler_below_target_not_saturated";
end
end
