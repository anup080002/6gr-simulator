function state = resolveAntennaState(llsCfg)
%RESOLVEANTENNASTATE Build the immutable physical-array execution state.
%
% The returned port-to-element matrix is the matrix actually applied to the
% logical PDSCH/PUSCH waveform before nrCDLChannel.  The same descriptor is
% consumed by exportAntennaArtifacts, so plotted patterns cannot silently
% describe a different array from the one used by the waveform.

arguments
    llsCfg (1,1) struct
end

enabled = logical(sixgr.util.structGet(llsCfg,"antenna.enabled",false));
state = struct( ...
    "Enabled",enabled, ...
    "StandardReference",string(sixgr.util.structGet( ...
        llsCfg,"antenna.standardReference","disabled")), ...
    "CouplingMode",string(sixgr.util.structGet( ...
        llsCfg,"antenna.couplingMode","disabled")), ...
    "PointingMode",string(sixgr.util.structGet( ...
        llsCfg,"antenna.pointingMode","disabled")), ...
    "PowerNormalization",string(sixgr.util.structGet( ...
        llsCfg,"antenna.powerNormalization","disabled")), ...
    "TxRole","", "RxRole","", "Tx",struct(), "Rx",struct());
if ~enabled
    return;
end

if exist("phased.NRAntennaElement","class") ~= 8 || ...
        exist("phased.NRRectangularPanelArray","class") ~= 8 || ...
        exist("phased.SteeringVector","class") ~= 8
    error("sixgr:lls:MissingPhasedArraySystemToolbox", ...
        "antenna.enabled=true requires phased.NRAntennaElement, " + ...
        "phased.NRRectangularPanelArray, and phased.SteeringVector.");
end

link = upper(string(llsCfg.simulation.link));
if link == "PDSCH"
    txRole = "gnb";
    rxRole = "ue";
else
    txRole = "ue";
    rxRole = "gnb";
end
numLogicalPorts = double(llsCfg.(lower(char(link))).numberAntennaPorts);
state.TxRole = txRole;
state.RxRole = rxRole;
state.Tx = localBuildRole(llsCfg,txRole,numLogicalPorts,true);
state.Rx = localBuildRole(llsCfg,rxRole,1,false);
end

function roleState = localBuildRole(cfg,role,numBeamPorts,isTransmitter)
roleCfg = cfg.antenna.(char(role));
fc = double(cfg.carrier.frequencyHz);
c = physconst("LightSpeed");
lambda = c / fc;
size4 = double(roleCfg.size(:).');
spacingLambda = double(roleCfg.spacingWavelength(:).');
polarizationAngles = double(roleCfg.polarizationAnglesDeg(:).');
frequencyRange = double(roleCfg.element.frequencyRangeHz(:).');
beamwidth = double(roleCfg.element.beamwidthDeg(:).');
sidelobe = double(roleCfg.element.sidelobeLevelDb(:).');

elementSet = cell(1,numel(polarizationAngles));
for index = 1:numel(polarizationAngles)
    elementSet{index} = phased.NRAntennaElement( ...
        "FrequencyRange",frequencyRange, ...
        "PolarizationAngle",polarizationAngles(index), ...
        "PolarizationModel",double(roleCfg.element.polarizationModel), ...
        "Beamwidth",beamwidth, ...
        "SidelobeLevel",sidelobe, ...
        "MaximumAttenuation",double(roleCfg.element.maximumAttenuationDb), ...
        "MaximumGain",double(roleCfg.element.maximumGainDbi));
end
array = phased.NRRectangularPanelArray( ...
    "ElementSet",elementSet, ...
    "Size",size4, ...
    "Spacing",spacingLambda .* lambda, ...
    "EnablePanelSubarray",false);
cleanup = onCleanup(@() release(array)); %#ok<NASGU>
positions = double(getElementPosition(array).');
numElements = double(getNumElements(array));
if size(positions,1) ~= numElements
    error("sixgr:lls:AntennaElementCountMismatch", ...
        "%s phased-array geometry returned %d positions for %d elements.", ...
        upper(char(role)),size(positions,1),numElements);
end

beamAngles = double(roleCfg.steeringAzElDeg);
if isvector(beamAngles)
    beamAngles = reshape(beamAngles,1,[]);
end
if isTransmitter && size(beamAngles,1) ~= numBeamPorts
    error("sixgr:lls:AntennaSteeringPortMismatch", ...
        "%s steeringAzElDeg has %d beam row(s), but the transmitted waveform has %d logical port(s).", ...
        upper(char(role)),size(beamAngles,1),numBeamPorts);
end
if ~isTransmitter
    beamAngles = beamAngles(1,:);
    numBeamPorts = 1;
end
steering = phased.SteeringVector( ...
    "SensorArray",array, ...
    "PropagationSpeed",c, ...
    "IncludeElementResponse",false);
weights = complex(zeros(numElements,numBeamPorts));
for port = 1:numBeamPorts
    raw = steering(fc,beamAngles(port,:).');
    raw = conj(raw(:));
    normValue = norm(raw);
    if ~(isfinite(normValue) && normValue > 0)
        error("sixgr:lls:InvalidAntennaSteeringVector", ...
            "%s beam %d produced an invalid steering-vector norm.", ...
            upper(char(role)),port);
    end
    weights(:,port) = raw ./ normValue;
end
gram = weights' * weights;
if any(~isfinite(gram),"all") || ...
        any(abs(real(diag(gram))-1) > 1e-12)
    error("sixgr:lls:InvalidAntennaPowerNormalization", ...
        "%s steering columns are not unit-power normalized.",upper(char(role)));
end

polModel = "Model-" + string(double(roleCfg.element.polarizationModel));
channelArray = struct( ...
    "size",[size4(1:2) numel(polarizationAngles) size4(3:4)], ...
    "elementSpacingWavelength",spacingLambda, ...
    "polarizationAnglesDeg",polarizationAngles, ...
    "orientationDeg",double(roleCfg.orientationDeg(:)), ...
    "element","38.901", ...
    "polarizationModel",polModel);
roleState = struct( ...
    "Role",role, ...
    "Model",string(roleCfg.model), ...
    "Architecture",string(roleCfg.architecture), ...
    "FrequencyHz",fc, ...
    "WavelengthM",lambda, ...
    "Size",size4, ...
    "ChannelArraySize",channelArray.size, ...
    "SpacingWavelength",spacingLambda, ...
    "OrientationDeg",double(roleCfg.orientationDeg(:).'), ...
    "PolarizationAnglesDeg",polarizationAngles, ...
    "PolarizationModel",double(roleCfg.element.polarizationModel), ...
    "ElementFrequencyRangeHz",frequencyRange, ...
    "ElementBeamwidthDeg",beamwidth, ...
    "ElementSidelobeLevelDb",sidelobe, ...
    "ElementMaximumAttenuationDb",double(roleCfg.element.maximumAttenuationDb), ...
    "ElementMaximumGainDbi",double(roleCfg.element.maximumGainDbi), ...
    "NumElements",numElements, ...
    "NumRFChains",double(roleCfg.numRFChains), ...
    "NumLogicalPorts",numBeamPorts, ...
    "ElementPositionsM",positions, ...
    "SteeringAzElDeg",beamAngles, ...
    "PortToElementMatrix",weights, ...
    "PortToElementSHA256",localComplexHash(weights), ...
    "ChannelArray",channelArray, ...
    "PatternSource","phased.NRRectangularPanelArray_with_phased.NRAntennaElement", ...
    "PatternAppliedBy","nrCDLChannel_38.901_element_and_physical_array_geometry");
end

function digest = localComplexHash(value)
bytes = [typecast(double(real(value(:))),"uint8") typecast(double(imag(value(:))),"uint8")];
digest = sixgr.util.sha256Hex(bytes(:));
end
