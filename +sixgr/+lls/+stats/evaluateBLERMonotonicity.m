function result = evaluateBLERMonotonicity(summaryTable)
%EVALUATEBLERMONOTONICITY Detect confidence-separated BLER inversions.
%
% Finite Monte-Carlo estimates are not guaranteed to be numerically
% monotone, especially in saturated zero- or unit-error regions.  Reject a
% curve only when a higher-SNR confidence interval is wholly above a
% lower-SNR interval.  This does not smooth, reorder, or replace measured
% BLER values; it is solely a statistically defensible data-quality gate.

arguments
    summaryTable table
end

required = ["SNRdB","BLER","BLERLowerCI","BLERUpperCI"];
missing = setdiff(required,string(summaryTable.Properties.VariableNames));
if ~isempty(missing)
    error("sixgr:lls:MissingBLERMonotonicityColumns", ...
        "BLER monotonicity evaluation requires columns: %s.", ...
        strjoin(missing,", "));
end
if isempty(summaryTable)
    error("sixgr:lls:EmptyBLERMonotonicityInput", ...
        "BLER monotonicity evaluation requires at least one measured point.");
end

snr = double(summaryTable.SNRdB(:));
bler = double(summaryTable.BLER(:));
lower = double(summaryTable.BLERLowerCI(:));
upper = double(summaryTable.BLERUpperCI(:));
tolerance = 1e-12;
if any(~isfinite([snr;bler;lower;upper])) || ...
        any(bler < 0 | bler > 1) || any(lower < 0 | upper > 1) || ...
        any(lower > bler+tolerance | bler > upper+tolerance) || ...
        numel(unique(snr)) ~= numel(snr)
    error("sixgr:lls:InvalidBLERMonotonicityInput", ...
        "SNR, BLER, and confidence bounds must be finite, unique, ordered binomial evidence.");
end

[snr,order] = sort(snr,"ascend");
bler = bler(order);
lower = lower(order);
upper = upper(order);
empiricalNonincreasing = all(diff(bler) <= tolerance);

rows = repmat(struct("LowerSNRdB",0,"HigherSNRdB",0, ...
    "LowerSNRBLER",0,"HigherSNRBLER",0, ...
    "LowerSNRUpperCI",0,"HigherSNRLowerCI",0, ...
    "ConfidenceSeparatedInversion",false),0,1);
for lowIndex = 1:numel(snr)-1
    for highIndex = lowIndex+1:numel(snr)
        inversion = lower(highIndex) > upper(lowIndex) + tolerance;
        if inversion
            rows(end+1,1) = struct( ... %#ok<AGROW>
                "LowerSNRdB",snr(lowIndex), ...
                "HigherSNRdB",snr(highIndex), ...
                "LowerSNRBLER",bler(lowIndex), ...
                "HigherSNRBLER",bler(highIndex), ...
                "LowerSNRUpperCI",upper(lowIndex), ...
                "HigherSNRLowerCI",lower(highIndex), ...
                "ConfidenceSeparatedInversion",true);
        end
    end
end
if isempty(rows)
    inversionTable = table('Size',[0 7], ...
        'VariableTypes',[repmat("double",1,6),"logical"], ...
        'VariableNames',{'LowerSNRdB','HigherSNRdB','LowerSNRBLER', ...
        'HigherSNRBLER','LowerSNRUpperCI','HigherSNRLowerCI', ...
        'ConfidenceSeparatedInversion'});
else
    inversionTable = struct2table(rows);
end

result = struct( ...
    "StatisticallyNoninverted",isempty(rows), ...
    "EmpiricalNonincreasing",logical(empiricalNonincreasing), ...
    "PointCount",double(numel(snr)), ...
    "InversionCount",double(numel(rows)), ...
    "Method","all_pair_confidence_interval_noninversion", ...
    "MeasuredValuesModified",false, ...
    "Inversions",inversionTable);
end
