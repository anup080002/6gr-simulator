function state = resolveNTNState(llsCfg, sampleRateHz)
%RESOLVENTNSTATE Resolve configured NTN geometry into runtime channel values.
%
% The geometry is evaluated using Satellite Communications Toolbox.  This
% helper returns physical, compensation, and residual Doppler separately so
% an ideal common-Doppler correction can never be mistaken for zero motion.

arguments
    llsCfg (1,1) struct
    sampleRateHz (1,1) double {mustBePositive,mustBeFinite}
end

enabled = logical(sixgr.util.structGet(llsCfg, "ntn.enabled", false));
state = struct( ...
    "Enabled", enabled, ...
    "Profile", string(llsCfg.channel.model), ...
    "OrbitType", "", ...
    "PayloadArchitecture", "", ...
    "SatelliteAltitudeM", 0, ...
    "GroundAltitudeM", 0, ...
    "ElevationAngleDeg", 0, ...
    "SlantRangeM", 0, ...
    "PropagationDelayEnabled", false, ...
    "PropagationDelaySeconds", 0, ...
    "PropagationDelaySamples", 0, ...
    "PropagationDelayCompensationMode", "disabled", ...
    "PhysicalSatelliteDopplerHz", 0, ...
    "MobileMaximumDopplerHz", 0, ...
    "DopplerCompensationMode", "none", ...
    "DopplerCompensationHz", 0, ...
    "ResidualSatelliteDopplerHz", 0, ...
    "GeometrySource", "disabled");
if ~enabled
    return;
end

if exist("slantRangeCircularOrbit", "file") ~= 2 || ...
        exist("dopplerShiftCircularOrbit", "file") ~= 2
    error("sixgr:lls:MissingSatelliteCommunicationsToolbox", ...
        "NTN waveform execution requires slantRangeCircularOrbit and " + ...
        "dopplerShiftCircularOrbit from Satellite Communications Toolbox.");
end

orbit = llsCfg.ntn.orbit;
doppler = llsCfg.ntn.doppler;
delay = llsCfg.ntn.propagationDelay;
fc = double(llsCfg.carrier.frequencyHz);
altitudeM = double(orbit.satelliteAltitudeM);
groundAltitudeM = double(orbit.groundAltitudeM);
elevationDeg = double(orbit.elevationAngleDeg);
slantRangeM = double(slantRangeCircularOrbit( ...
    elevationDeg, altitudeM, groundAltitudeM));
physicalSatelliteDopplerHz = 0;
if logical(doppler.satelliteMotionEnabled)
    physicalSatelliteDopplerHz = double(dopplerShiftCircularOrbit( ...
        elevationDeg, altitudeM, groundAltitudeM, fc));
end
mobileDopplerHz = 0;
if logical(doppler.mobileMotionEnabled)
    mobileDopplerHz = double(llsCfg.channel.velocityKmph) / 3.6 * ...
        fc / 299792458;
end

compensationMode = lower(string(doppler.compensationMode));
switch compensationMode
    case "none"
        compensationHz = 0;
    case {"ideal_transmitter_geometry", "ideal_receiver_geometry"}
        compensationHz = physicalSatelliteDopplerHz;
    otherwise
        error("sixgr:lls:InvalidNTNDopplerCompensation", ...
            "Unsupported ntn.doppler.compensationMode '%s'.", ...
            compensationMode);
end
residualSatelliteDopplerHz = physicalSatelliteDopplerHz - compensationHz;

propagationDelaySeconds = 0;
propagationDelaySamples = 0;
if logical(delay.enabled)
    propagationDelaySeconds = slantRangeM / 299792458;
    propagationDelaySamples = round(propagationDelaySeconds * sampleRateHz);
end

state = struct( ...
    "Enabled", true, ...
    "Profile", string(llsCfg.channel.model), ...
    "OrbitType", string(orbit.type), ...
    "PayloadArchitecture", string(llsCfg.ntn.payload.architecture), ...
    "SatelliteAltitudeM", altitudeM, ...
    "GroundAltitudeM", groundAltitudeM, ...
    "ElevationAngleDeg", elevationDeg, ...
    "SlantRangeM", slantRangeM, ...
    "PropagationDelayEnabled", logical(delay.enabled), ...
    "PropagationDelaySeconds", propagationDelaySeconds, ...
    "PropagationDelaySamples", propagationDelaySamples, ...
    "PropagationDelayCompensationMode", string(delay.compensationMode), ...
    "PhysicalSatelliteDopplerHz", physicalSatelliteDopplerHz, ...
    "MobileMaximumDopplerHz", mobileDopplerHz, ...
    "DopplerCompensationMode", string(doppler.compensationMode), ...
    "DopplerCompensationHz", compensationHz, ...
    "ResidualSatelliteDopplerHz", residualSatelliteDopplerHz, ...
    "GeometrySource", ...
        "Satellite_Communications_Toolbox_circular_orbit_geometry");
end
