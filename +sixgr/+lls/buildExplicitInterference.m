function [interferenceWaveform,info] = buildExplicitInterference( ...
        desiredWaveform,carrier,llsCfg,phyCfg,snrIndex,trialIndex)
%BUILDEXPLICITINTERFERENCE Generate one actual cochannel interferer.
% The interferer owns independent TB bits and channel/noise streams. Its
% receive power is calibrated to the YAML D/I ratio at the common receiver;
% no SINR-to-BLER or random pass/fail abstraction is involved.

enabled = logical(sixgr.util.structGet(llsCfg,"interference.enabled",false));
info = struct( ...
    "Enabled",enabled,"WaveformCount",0,"ConfiguredDIRdB",NaN, ...
    "MeasuredDIRdB",NaN,"DesiredPower",NaN,"InterferencePower",0, ...
    "Source","disabled","InterfererBitSeed",NaN,"InterfererChannelSeed",NaN);
interferenceWaveform = complex(zeros(size(desiredWaveform),"like",desiredWaveform));
if ~enabled
    return;
end

dirDb = double(llsCfg.interference.desiredToInterferenceRatioDb);
randomnessKey = string(sixgr.util.structGet(llsCfg, ...
    "simulation.commonRandomKey",llsCfg.scenario.id));
bitSeed = sixgr.lls.deterministicSeed(llsCfg.simulation.masterSeed, ...
    randomnessKey,snrIndex,trialIndex,"interferer_transport_bits");
channelSeed = sixgr.lls.deterministicSeed(llsCfg.interference.channel.seed, ...
    randomnessKey,snrIndex,trialIndex,"interferer_channel");
interfererPHY = phyCfg;
link = upper(string(llsCfg.simulation.link));
if link == "PUSCH"
    interfererPHY.phy.pusch.RNTI = double(llsCfg.interference.rnti);
    interfererPHY.phy.pusch.NID = double(llsCfg.interference.nid);
else
    interfererPHY.phy.pdsch.RNTI = double(llsCfg.interference.rnti);
    interfererPHY.phy.pdsch.NID = double(llsCfg.interference.nid);
end
previous = rng;
restore = onCleanup(@()rng(previous)); %#ok<NASGU>
rng(bitSeed,"twister");
if link == "PUSCH"
    tx = sixgr.phy.ul.PUSCH_Tx(interfererPHY, ...
        "NumTxAnt",double(llsCfg.interference.channel.txAntennas), ...
        "CompactOutput",false);
else
    tx = sixgr.phy.dl.PDSCH_Tx(interfererPHY, ...
        "ExecutionProfile","phy_calibration", ...
        "NumTxAnt",double(llsCfg.interference.channel.txAntennas), ...
        "CompactOutput",false);
end
interfererCfg = llsCfg;
interfererCfg.channel = llsCfg.interference.channel;
[rawInterference,~,channelInfo] = sixgr.lls.applyChannel( ...
    tx.Waveform,carrier,interfererCfg,channelSeed);
if ~isequal(size(rawInterference),size(desiredWaveform))
    error("sixgr:lls:InterferenceWaveformShapeMismatch", ...
        "Desired waveform size %s and interferer receive waveform size %s differ.", ...
        mat2str(size(desiredWaveform)),mat2str(size(rawInterference)));
end
desiredPower = mean(abs(desiredWaveform).^2,"all");
rawPower = mean(abs(rawInterference).^2,"all");
if ~(isfinite(desiredPower) && desiredPower > 0 && isfinite(rawPower) && rawPower > 0)
    error("sixgr:lls:InvalidInterferencePower", ...
        "Desired and interferer receive powers must be finite and positive.");
end
targetInterferencePower = desiredPower/10^(dirDb/10);
interferenceWaveform = rawInterference*sqrt(targetInterferencePower/rawPower);
measuredPower = mean(abs(interferenceWaveform).^2,"all");
info = struct( ...
    "Enabled",true,"WaveformCount",1,"ConfiguredDIRdB",dirDb, ...
    "MeasuredDIRdB",10*log10(desiredPower/measuredPower), ...
    "DesiredPower",desiredPower,"InterferencePower",measuredPower, ...
    "Source","independent_transport_block_waveform_and_channel", ...
    "InterfererBitSeed",double(bitSeed), ...
    "InterfererChannelSeed",double(channelSeed), ...
    "InterfererChannelSource",string(channelInfo.Source));
end
