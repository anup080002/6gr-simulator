function [report, valid] = validateResults(cfg, summaryTable, trialTable, truthContract,varargin)
%VALIDATERESULTS Evaluate fail-closed scientific result invariants.

toleranceDb = double(sixgr.util.structGet(cfg, "results.snrCalibrationToleranceDb", 0.5));
harqEnabled = logical(sixgr.util.structGet(cfg,"harq.enabled",false));
harqMetricsValid = localHARQMetricsValid(summaryTable,trialTable,harqEnabled);
interferenceValid = localInterferenceValid(cfg,trialTable);
linkAdaptationValid = localLinkAdaptationValid(cfg,trialTable);
fixedMCSValid = logical(sixgr.util.structGet(cfg,"linkAdaptation.enabled",false)) || ...
    (numel(unique(trialTable.TransportBlockSizeBits)) == 1 && ...
    numel(unique(trialTable.CodedBitsG)) == 1 && ...
    numel(unique(trialTable.TargetCodeRate)) == 1 && ...
    numel(unique(trialTable.ModulationOrder)) == 1);
mcsBindingValid = localMCSBindingValid(cfg,trialTable);
receiverNoisePolicyValid = localReceiverNoisePolicyValid(cfg,trialTable);
ntnChannelValid = localNTNChannelValid(cfg,trialTable);
antennaChannelValid = localAntennaChannelValid(cfg,trialTable);
isacValid = localISACValid(cfg,trialTable);
studyType = lower(string(sixgr.util.structGet(cfg,"simulation.studyType","fixed_mcs_bler")));
isLinkAdaptationStudy = studyType == "link_adaptation_throughput";
linkAdaptationResponseValid = true;
if isLinkAdaptationStudy
    linkAdaptationResponseValid = localLinkAdaptationOperatingResponseValid( ...
        cfg,summaryTable,trialTable);
end
requiredSNRValid = true;
requiresPublicationTarget = ...
    string(cfg.simulation.statisticalClass) == "publication_candidate" && ...
    ismember(studyType,["fixed_mcs_bler","interference_bler"]);
if requiresPublicationTarget
    requiredSNRValid = ~isempty(varargin) && istable(varargin{1}) && ...
        ~isempty(varargin{1}) && all(varargin{1}.Valid);
end
monotonicity = sixgr.lls.stats.evaluateBLERMonotonicity(summaryTable);
if isLinkAdaptationStudy
    blerShapePass = true;
    blerShapeEvidence = [ ...
        "not applicable to adaptive-MCS operation: each SNR can execute a " + ...
        "different modulation/code rate; causal target tracking and saturation " + ...
        "are validated by link_adaptation_operating_response"];
else
    blerShapePass = monotonicity.StatisticallyNoninverted;
    blerShapeEvidence = [ ...
        "no higher-SNR BLER confidence interval lies wholly above a lower-SNR " + ...
        "interval; raw estimates are not smoothed"];
end
checks = [ ...
    localCheck("bler_range", all(summaryTable.BLER >= 0 & summaryTable.BLER <= 1), "0 <= BLER <= 1");
    localCheck("bler_statistical_noninversion", ...
        blerShapePass,blerShapeEvidence);
    localCheck("error_counts", all(summaryTable.NumBlockErrors <= summaryTable.NumTB), "block errors do not exceed transmitted TBs");
    localCheck("confidence_intervals", all(summaryTable.BLERLowerCI >= 0 & summaryTable.BLERUpperCI <= 1 & ...
        summaryTable.BLERLowerCI <= summaryTable.BLER+1e-12 & ...
        summaryTable.BLER <= summaryTable.BLERUpperCI+1e-12), ...
        "Wilson confidence intervals contain empirical BLER");
    localCheck("decoder_crc_authority", all(trialTable.CRCSource == "decoded_transport_block_crc"), ...
        "every ACK/NACK comes from decoded TB CRC");
    localCheck("soft_llr_authority", all(trialTable.LLRSource == ...
        "nr" + upper(string(cfg.simulation.link)) + "Decode_soft_llr"), ...
        "LDPC receives waveform-derived soft LLRs");
    localCheck("ldpc_backend_authority", ...
        truthContract.ConfiguredLDPCBackendExecuted, ...
        "runtime MATLAB/MEX LDPC backend matches receiver.useMexLDPC and remains exact decoded truth");
    localCheck("snr_calibration", all(abs(trialTable.MeasuredSNRdB-trialTable.TargetSNRdB) <= toleranceDb), ...
        compose("every measured injected Es/N0 is within %.3g dB", toleranceDb));
    localCheck("configuration_hash", all(strlength(trialTable.ConfigSHA256) == 64), ...
        "every trial contains a SHA-256 configuration hash");
    localCheck("fixed_mcs_tbs", fixedMCSValid, ...
        "fixed-MCS studies hold TBS/G/code-rate/modulation; AMC studies prove exact per-trial binding");
    localCheck("mcs_configuration_binding",mcsBindingValid, ...
        "every trial reports the MCS-table authority that selected its executed modulation and code rate");
    localCheck("receiver_noise_policy_authority",receiverNoisePolicyValid, ...
        "configured residual bounds and decoder-noise domain match every executed receiver trial without hidden fallback");
    localCheck("ntn_channel_authority",ntnChannelValid && truthContract.NTNEvidenceValid, ...
        "enabled NTN uses exact runtime orbit, delay, Doppler and NTN-TDL/CDL waveform evidence");
    localCheck("antenna_array_authority",antennaChannelValid && truthContract.AntennaEvidenceValid, ...
        "enabled BS/UE arrays use unit-power logical-port projection and the physical-element CDL channel");
    localCheck("isac_sensing_authority",isacValid && truthContract.ISACEvidenceValid, ...
        "enabled ISAC reuses the exact PDSCH waveform and exports measured scattering-channel range/angle/Doppler evidence");
    localCheck("harq_metric_separation",harqMetricsValid, ...
        "first-transmission BLER, post-HARQ residual BLER, attempts, and throughput are separate");
    localCheck("explicit_interference_authority",interferenceValid, ...
        "enabled interference is an independently encoded/channelized waveform at calibrated D/I");
    localCheck("causal_link_adaptation_authority",linkAdaptationValid, ...
        "AMC consumes only prior receiver measurements and each selected MCS executes through waveform truth");
    localCheck("link_adaptation_operating_response",linkAdaptationResponseValid, ...
        "adaptive-MCS studies contain per-SNR causal CQI/ILLA/OLLA runtime reductions with explicit target-tracking and terminal-saturation classification");
    localCheck("publication_statistics", ...
        string(cfg.simulation.statisticalClass) ~= "publication_candidate" || ...
        (truthContract.ConfiguredPublicationBudget && ...
        truthContract.ExecutedStoppingRuleSatisfied && truthContract.PublicationEligible), ...
        "publication eligibility requires both configured budgets and executed stopping-rule evidence");
    localCheck("required_snr_targets",requiredSNRValid, ...
        "publication fixed-MCS target BLERs have empirical or confidence-bracketed simulated crossings");
    localCheck("truth_contract", all(truthContract{1,["WaveformGenerated","ActualLDPC", ...
        "ActualRateMatching","ActualDMRS","ActualChannel","ActualNoise", ...
        "ActualEqualization","ActualSoftDemapping","ActualLDPCDecode","ActualCRC", ...
        "ConfiguredLDPCBackendExecuted"]}), ...
        "required waveform truth blocks executed");
    localCheck("no_link_abstraction", ~truthContract.UsesBLERLookupTable && ...
        ~truthContract.UsesSyntheticBLER && ~truthContract.UsesRandomPassFailModel && ...
        ~truthContract.UsesGeometryAsLLS, ...
        "no lookup/synthetic/random-pass/geometry LLS source was active")];
report = struct2table(checks);
valid = all(report.Pass);
end

function valid = localLinkAdaptationOperatingResponseValid(cfg,summary,trials)
if ~logical(sixgr.util.structGet(cfg,"linkAdaptation.enabled",false))
    valid = false;
    return;
end
operating = sixgr.lls.buildLinkAdaptationOperatingPointSummary(cfg,summary,trials);
expectedPoints = numel(unique(double(trials.SNRIndex)));
valid = height(operating) == expectedPoints && ...
    all(operating.RuntimeTrials > 0) && ...
    all(operating.PostDelayEvaluationTrials > 0) && ...
    all(operating.ILLAFeedbackAppliedTrials == ...
        operating.PostDelayEvaluationTrials) && ...
    all(operating.BootstrapTrials + operating.PostDelayEvaluationTrials == ...
        operating.RuntimeTrials) && ...
    all(operating.SchedulerEligibleTrials + ...
        operating.DiagnosticWaveformProbeTrials == operating.RuntimeTrials) && ...
    all(isfinite(operating.PostDelayBLER)) && ...
    all(operating.PostDelayBLER >= 0 & operating.PostDelayBLER <= 1) && ...
    all(strlength(operating.TargetTrackingClassification) > 0) && ...
    all(operating.ExecutionBackend == "waveform_truth") && ...
    all(operating.ApproximationMode == "none");
if logical(cfg.linkAdaptation.olla.enabled)
    valid = valid && all(operating.OLLAUpdateCount == ...
        operating.PostDelayEvaluationTrials) && ...
        all(operating.OLLAACKCount + operating.OLLANACKCount == ...
        operating.PostDelayEvaluationTrials);
end
end

function valid = localISACValid(cfg,trials)
enabled = logical(sixgr.util.structGet(cfg,"isac.enabled",false));
required = ["ISACEnabled","ISACSensingExecuted","ISACEvidenceValid", ...
    "ISACLogicalWaveformSHA256","ISACMatchedTargetCount", ...
    "ISACRangeRMSEM","ISACAzimuthRMSEDeg"];
hasFields = all(ismember(required,string(trials.Properties.VariableNames)));
if ~enabled
    valid = ~hasFields || (~any(trials.ISACEnabled) && ...
        ~any(trials.ISACSensingExecuted));
    return;
end
if ~hasFields
    valid = false;
    return;
end
captured = trials.ISACSensingExecuted;
valid = all(trials.ISACEnabled) && nnz(captured) == 1 && ...
    all(trials.ISACEvidenceValid(captured)) && ...
    all(strlength(trials.ISACLogicalWaveformSHA256(captured)) == 64) && ...
    all(trials.ISACMatchedTargetCount(captured) >= ...
        double(cfg.isac.acceptance.minimumMatchedTargets)) && ...
    all(trials.ISACRangeRMSEM(captured) <= ...
        double(cfg.isac.acceptance.maximumRangeErrorM)) && ...
    all(trials.ISACAzimuthRMSEDeg(captured) <= ...
        double(cfg.isac.acceptance.maximumAzimuthErrorDeg));
end

function valid = localAntennaChannelValid(cfg,trials)
required = ["AntennaEnabled","AntennaCouplingMode", ...
    "AntennaTxPhysicalElements","AntennaRxPhysicalElements", ...
    "AntennaTxLogicalPorts","AntennaTxPortToElementSHA256", ...
    "AntennaPatternSource","AntennaPhysicalElementChannelApplied"];
valid = all(ismember(required,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
enabled = logical(cfg.antenna.enabled);
if ~enabled
    valid = ~any(trials.AntennaEnabled) && ...
        ~any(trials.AntennaPhysicalElementChannelApplied);
    return;
end
state = sixgr.lls.resolveAntennaState(cfg);
valid = all(trials.AntennaEnabled) && ...
    all(trials.AntennaPhysicalElementChannelApplied) && ...
    all(trials.AntennaCouplingMode == "cdl_physical_element_domain") && ...
    all(trials.AntennaTxPhysicalElements == state.Tx.NumElements) && ...
    all(trials.AntennaRxPhysicalElements == state.Rx.NumElements) && ...
    all(trials.AntennaTxLogicalPorts == state.Tx.NumLogicalPorts) && ...
    all(trials.AntennaTxPortToElementSHA256 == state.Tx.PortToElementSHA256) && ...
    all(trials.AntennaPatternSource == state.Tx.PatternSource) && ...
    all(trials.NumRxAntennas == state.Rx.NumElements) && ...
    all(contains(trials.ChannelRealizationSource,"nrCDLChannel"));
end

function valid = localNTNChannelValid(cfg,trials)
required = ["NTNEnabled","NTNProfile","NTNSlantRangeM", ...
    "NTNPropagationDelaySeconds","NTNPropagationDelaySamples", ...
    "NTNPhysicalSatelliteDopplerHz","NTNDopplerCompensationHz", ...
    "NTNResidualSatelliteDopplerHz","NTNSampleRateHz","NTNGeometrySource"];
valid = all(ismember(required,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
enabled = logical(cfg.ntn.enabled);
if ~enabled
    valid = ~any(trials.NTNEnabled) && all(trials.NTNGeometrySource == "disabled");
    return;
end
sampleRates = unique(double(trials.NTNSampleRateHz));
if numel(sampleRates) ~= 1 || sampleRates <= 0
    valid = false;
    return;
end
state = sixgr.lls.resolveNTNState(cfg,sampleRates);
relativeTolerance = @(actual,target) abs(double(actual)-double(target)) <= ...
    128*eps(max(abs(double(target)),1));
valid = all(trials.NTNEnabled) && ...
    all(trials.NTNProfile == string(cfg.channel.model)) && ...
    all(relativeTolerance(trials.NTNSlantRangeM,state.SlantRangeM)) && ...
    all(relativeTolerance(trials.NTNPropagationDelaySeconds,state.PropagationDelaySeconds)) && ...
    all(trials.NTNPropagationDelaySamples == state.PropagationDelaySamples) && ...
    all(relativeTolerance(trials.NTNPhysicalSatelliteDopplerHz, ...
        state.PhysicalSatelliteDopplerHz)) && ...
    all(relativeTolerance(trials.NTNDopplerCompensationHz,state.DopplerCompensationHz)) && ...
    all(relativeTolerance(trials.NTNResidualSatelliteDopplerHz, ...
        state.ResidualSatelliteDopplerHz)) && ...
    all(trials.NTNGeometrySource == state.GeometrySource);
end

function valid = localMCSBindingValid(cfg,trials)
required = ["MCSTable","MCSIndex","Modulation","TargetCodeRate"];
valid = all(ismember(required,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
expectedTable = sixgr.lls.executedMCSTable(cfg);
valid = all(trials.MCSTable == expectedTable);
if ~valid || logical(sixgr.util.structGet(cfg,"linkAdaptation.enabled",false))
    return;
end
link = lower(string(cfg.simulation.link));
linkCfg = cfg.(char(link));
valid = all(trials.MCSIndex == double(linkCfg.mcsIndex)) && ...
    all(strcmpi(trials.Modulation,string(linkCfg.modulation))) && ...
    all(abs(trials.TargetCodeRate-double(linkCfg.targetCodeRate)) <= 1e-12);
end

function valid = localReceiverNoisePolicyValid(cfg,trials)
required = ["DMRSResidualPostEqSINRBoundEnabled", ...
    "DecisionDirectedPostEqSINRBoundEnabled", ...
    "PostEqSINRDMRSResidualBoundApplied","DecoderNoiseVariance", ...
    "DecoderNoiseVarianceSource","DecoderNoiseVarianceConfiguredMode", ...
    "LLRNoiseVariance", ...
    "LLRNoiseVarianceSource","LLRNoiseVarianceDomain"];
valid = all(ismember(required,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
dmrsEnabled = logical(cfg.receiver.postEqualizationSINR.dmrsResidualBoundEnabled);
decisionEnabled = logical(cfg.receiver.postEqualizationSINR.decisionDirectedResidualBoundEnabled);
valid = all(trials.DMRSResidualPostEqSINRBoundEnabled == dmrsEnabled) && ...
    all(trials.DecisionDirectedPostEqSINRBoundEnabled == decisionEnabled) && ...
    all(isfinite(trials.DecoderNoiseVariance) & trials.DecoderNoiseVariance > 0) && ...
    all(isfinite(trials.LLRNoiseVariance) & trials.LLRNoiseVariance > 0) && ...
    all(abs(trials.DecoderNoiseVariance-trials.LLRNoiseVariance) <= ...
        64*eps(max(abs(trials.DecoderNoiseVariance),1))) && ...
    all(strlength(trials.DecoderNoiseVarianceSource) > 0) && ...
    all(trials.DecoderNoiseVarianceConfiguredMode == ...
        string(cfg.receiver.decoderNoiseVariance.mode)) && ...
    all(strlength(trials.LLRNoiseVarianceSource) > 0) && ...
    all(strlength(trials.LLRNoiseVarianceDomain) > 0) && ...
    ~any(contains(lower(trials.DecoderNoiseVarianceSource),"fallback"));
if ~valid
    return;
end
if ~dmrsEnabled && ~decisionEnabled
    valid = ~any(trials.PostEqSINRDMRSResidualBoundApplied) && ...
        ~any(contains(lower(trials.PostEqSINRSource),"bounded"));
end
end

function valid = localLinkAdaptationValid(cfg,trials)
[valid,~] = sixgr.lls.validateLinkAdaptationTrialEvidence(cfg,trials);
end

function valid = localInterferenceValid(cfg,trials)
required = ["InterferenceEnabled","InterfererWaveformCount","ConfiguredDIRdB", ...
    "MeasuredDIRdB","MeasuredPreEqualizationSINRdB","InterferenceSource"];
valid = all(ismember(required,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
enabled = logical(sixgr.util.structGet(cfg,"interference.enabled",false));
if enabled
    valid = all(trials.InterferenceEnabled) && ...
        all(trials.InterfererWaveformCount == 1) && ...
        all(trials.InterferenceSource == "independent_transport_block_waveform_and_channel") && ...
        all(abs(trials.ConfiguredDIRdB-trials.MeasuredDIRdB) <= 0.05) && ...
        all(isfinite(trials.MeasuredPreEqualizationSINRdB));
else
    valid = ~any(trials.InterferenceEnabled) && ...
        all(trials.InterfererWaveformCount == 0) && ...
        all(trials.InterferenceSource == "disabled");
end
end

function valid = localHARQMetricsValid(summary,trials,enabled)
if ~enabled
    valid = ~any(trials.IsRetransmission) && ~any(trials.HARQSoftCombiningApplied);
    return;
end
requiredSummary = ["FirstTransmissionBLER","PostHARQResidualBLER", ...
    "AverageTransmissions","NumTransmissions"];
requiredTrials = ["PacketIndex","AttemptIndex","FirstTransmissionCRCError", ...
    "FinalPacketCRCError","PacketTransmissions"];
valid = all(ismember(requiredSummary,string(summary.Properties.VariableNames))) && ...
    all(ismember(requiredTrials,string(trials.Properties.VariableNames)));
if ~valid
    return;
end
valid = all(summary.BLER == summary.FirstTransmissionBLER) && ...
    all(summary.PostHARQResidualBLER <= summary.FirstTransmissionBLER + eps) && ...
    all(summary.AverageTransmissions >= 1) && ...
    all(trials.HARQSoftCombiningApplied(trials.AttemptIndex > 1));
end

function row = localCheck(name, pass, evidence)
row = struct("Check",string(name),"Pass",logical(pass), ...
    "Status",string(localStatus(pass)),"Evidence",string(evidence));
end

function value = localStatus(pass)
if pass
    value = "PASS";
else
    value = "FAIL";
end
end
