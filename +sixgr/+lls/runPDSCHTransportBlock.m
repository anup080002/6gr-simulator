function [row, diagnostic] = runPDSCHTransportBlock(llsCfg, phyCfg, configHash, snrIndex, trialIndex, varargin)
%RUNPDSCHTRANSPORTBLOCK Execute one production PDSCH/DL-SCH waveform trial.

% This adapter intentionally delegates coding, rate matching, scrambling,
% modulation, resource mapping, OFDM, soft demapping, rate recovery, LDPC
% decoding, and CRC authority to the existing production PDSCH Tx/Rx pair.

arguments
    llsCfg (1,1) struct
    phyCfg (1,1) struct
    configHash (1,1) string
    snrIndex (1,1) double {mustBePositive,mustBeInteger}
    trialIndex (1,1) double {mustBePositive,mustBeInteger}
end
arguments (Repeating)
    varargin
end

ip = inputParser;
ip.FunctionName = "sixgr.lls.runPDSCHTransportBlock";
ip.addParameter("PacketIndex",trialIndex,@(x) isnumeric(x) && isscalar(x) && x >= 1 && x == fix(x));
ip.addParameter("AttemptIndex",1,@(x) isnumeric(x) && isscalar(x) && x >= 1 && x == fix(x));
ip.addParameter("TransportBlockBits",[],@(x) isempty(x) || isnumeric(x) || islogical(x) || iscell(x));
ip.addParameter("RV",[],@(x) isempty(x) || (isnumeric(x) && isvector(x) && all(x >= 0 & x <= 3)));
ip.addParameter("HARQSoftBuffer",[],@(x) isempty(x) || isnumeric(x) || isstruct(x) || iscell(x));
ip.addParameter("HARQSoftBufferLayout",struct(),@(x) isempty(x) || isstruct(x) || iscell(x));
ip.addParameter("CaptureDiagnostic",true,@(x) (islogical(x) || isnumeric(x)) && isscalar(x));
ip.parse(varargin{:});
runtime = ip.Results;

snrDb = double(llsCfg.simulation.snrDb(snrIndex));
randomnessKey = string(sixgr.util.structGet(llsCfg, ...
    "simulation.commonRandomKey", llsCfg.scenario.id));
bitSeed = sixgr.lls.deterministicSeed(llsCfg.simulation.masterSeed, ...
    randomnessKey, snrIndex, runtime.PacketIndex, "transport_bits");
noiseSeed = sixgr.lls.deterministicSeed(llsCfg.simulation.masterSeed, ...
    randomnessKey, snrIndex, trialIndex, "awgn");
channelSeed = sixgr.lls.deterministicSeed(llsCfg.channel.seed, ...
    randomnessKey, snrIndex, trialIndex, "channel");

phyCfg.phy.carrier.NSlot = mod(trialIndex-1, ...
    10 * round(double(phyCfg.phy.carrier.SubcarrierSpacing)/15));
previousRng = rng;
restoreRng = onCleanup(@() rng(previousRng)); %#ok<NASGU>
rng(bitSeed, "twister");
trialClock = tic;
[tx, txInfo] = sixgr.phy.dl.PDSCH_Tx(phyCfg, ...
    "ExecutionProfile", "phy_calibration", ...
    "NumTxAnt", double(llsCfg.pdsch.numberAntennaPorts), ...
    "TransportBlockBits",runtime.TransportBlockBits, ...
    "RV",runtime.RV, ...
    "CompactOutput", false);

isacEnabled = logical(sixgr.util.structGet(llsCfg,"isac.enabled",false));
isacResult = struct();
isacExecuted = false;
isacEvidenceValid = ~isacEnabled;
isacDetectionCount = 0;
isacMatchedTargetCount = 0;
isacRangeRMSE = NaN;
isacAzimuthRMSE = NaN;
logicalWaveformHash = localComplexHash(tx.Waveform);
if isacEnabled && logical(runtime.CaptureDiagnostic)
    isacResult = sixgr.lls.runISACSensingTrial(llsCfg,tx);
    isacExecuted = true;
    isacEvidenceValid = logical(isacResult.EvidenceValid);
    isacDetectionCount = height(isacResult.DetectionTable);
    isacMatchedTargetCount = double(isacResult.RuntimeTable.MatchedTargetCount(1));
    isacRangeRMSE = double(isacResult.RuntimeTable.RangeRMSEM(1));
    isacAzimuthRMSE = double(isacResult.RuntimeTable.AzimuthRMSEDeg(1));
    if string(isacResult.LogicalWaveformSHA256) ~= string(logicalWaveformHash)
        error("sixgr:lls:ISACWaveformIdentityMismatch", ...
            "ISAC did not consume the exact runtime PDSCH waveform.");
    end
end

dataSymbols = tx.PDSCHSymbolsForEvidence(:);
signalEnergyPerOccupiedRE = mean(abs(dataSymbols).^2);
if ~(isscalar(signalEnergyPerOccupiedRE) && isfinite(signalEnergyPerOccupiedRE) ...
        && signalEnergyPerOccupiedRE > 0)
    error("sixgr:lls:InvalidOccupiedREEnergy", ...
        "PDSCH transmitter did not produce finite positive occupied-RE symbol energy.");
end
[channelWaveform, trueChannelGrid, channelInfo] = sixgr.lls.applyChannel( ...
    tx.Waveform, tx.Carrier, llsCfg, channelSeed);
[interferenceWaveform,interferenceInfo] = sixgr.lls.buildExplicitInterference( ...
    channelWaveform,tx.Carrier,llsCfg,phyCfg,snrIndex,trialIndex);
[noiseOnlyRxWaveform, noiseInfo] = sixgr.conformance.addReferenceNoise( ...
    channelWaveform, tx.Carrier, snrDb, ...
    "Seed", noiseSeed, ...
    "SignalEnergyPerOccupiedRE", signalEnergyPerOccupiedRE);
noiseWaveform = noiseOnlyRxWaveform - channelWaveform;
rxWaveform = noiseOnlyRxWaveform + interferenceWaveform;
[noiseGrid, noiseGridInfo] = sixgr.phy.waveform.ofdmDemodulate(tx.Carrier, noiseWaveform);
measuredGridNoiseVariance = mean(abs(noiseGrid(:)).^2);
measuredSNRdB = 10*log10(signalEnergyPerOccupiedRE / measuredGridNoiseVariance);

perfectEstimation = strcmpi(string(llsCfg.receiver.channelEstimation), "perfect");
receiverTrueChannel = [];
if perfectEstimation
    receiverTrueChannel = trueChannelGrid;
end
[rx, rxInfo] = sixgr.phy.dl.PDSCH_Rx(rxWaveform, phyCfg, ...
    "Carrier", tx.Carrier, ...
    "PDSCH", tx.PDSCH, ...
    "PDSCHIndices", tx.PDSCHIndices, ...
    "TransportBlockSize", tx.TransportBlockSize, ...
    "TargetCodeRate", tx.TargetCodeRate, ...
    "RV", tx.RV, ...
    "CodingPlan", tx.CodingPlans, ...
    "HARQSoftBufferLLR",runtime.HARQSoftBuffer, ...
    "HARQSoftBufferLayout",runtime.HARQSoftBufferLayout, ...
    "NoiseVar", noiseInfo.GridNoiseVariance, ...
    "NoiseVarDomain", "grid", ...
    "MaxIterations", double(llsCfg.receiver.ldpcMaxIterations), ...
    "Algorithm", char(string(llsCfg.receiver.ldpcAlgorithm)), ...
    "ExecutionProfile", "phy_calibration", ...
    "CompactOutput", false, ...
    "FastAWGNPath", strcmpi(string(llsCfg.channel.model), "AWGN"), ...
    "TrueChannel", receiverTrueChannel, ...
    "OracleTestMode", perfectEstimation, ...
    "SkipTimingEstimate", true);

txBits = int8(tx.TransportBlock(:));
rxBits = int8(rx.TransportBlock(:));
if numel(txBits) ~= numel(rxBits)
    bitErrors = numel(txBits);
else
    bitErrors = sum(txBits ~= rxBits);
end
crcError = logical(rx.CRCError);
if crcError ~= ~logical(rx.Ok)
    error("sixgr:lls:CRCStatusInconsistent", ...
        "PDSCH receiver Ok and CRCError fields are inconsistent.");
end

accounting = tx.ResourceAccounting;
runtimeSeconds = toc(trialClock);
row = struct( ...
    "ScenarioId", string(llsCfg.scenario.id), ...
    "ConfigSHA256", configHash, ...
    "SNRIndex", double(snrIndex), ...
    "TrialIndex", double(trialIndex), ...
    "PacketIndex", double(runtime.PacketIndex), ...
    "AttemptIndex", double(runtime.AttemptIndex), ...
    "IsRetransmission", logical(runtime.AttemptIndex > 1), ...
    "RV", double(tx.RV(1)), ...
    "HARQSoftCombiningApplied", logical(localPDSCHHARQCombiningApplied(rx)), ...
    "TargetSNRdB", snrDb, ...
    "MeasuredSNRdB", measuredSNRdB, ...
    "BitSeed", double(bitSeed), ...
    "NoiseSeed", double(noiseSeed), ...
    "ChannelSeed", double(channelSeed), ...
    "SynchronizationResidualEnabled",logical(channelInfo.SynchronizationResidualEnabled), ...
    "SynchronizationResidualTimingSeconds",double(channelInfo.SynchronizationResidualTimingSeconds), ...
    "SynchronizationResidualTimingSamples",double(channelInfo.SynchronizationResidualTimingSamples), ...
    "SynchronizationResidualFrequencyHz",double(channelInfo.SynchronizationResidualFrequencyHz), ...
    "SynchronizationResidualSource",string(channelInfo.SynchronizationResidualSource), ...
    "SynchronizationResidualReceiverOracleUsed",logical(channelInfo.SynchronizationResidualReceiverOracleUsed), ...
    "TransportBlockSizeBits", double(numel(txBits)), ...
    "BitErrors", double(bitErrors), ...
    "CRCError", crcError, ...
    "ACK", ~crcError, ...
    "DataREPerLayer", double(accounting.LayerDataRE), ...
    "DMRSRE", double(accounting.DMRSRE), ...
    "PTRSRE", double(accounting.PTRSRE), ...
    "ReservedRE", double(accounting.ReservedRE), ...
    "CodedBitsG", double(accounting.CodedBitCountG), ...
    "MCSIndex",double(llsCfg.pdsch.mcsIndex), ...
    "MCSTable",sixgr.lls.executedMCSTable(llsCfg), ...
    "Modulation",string(llsCfg.pdsch.modulation), ...
    "ModulationOrder", double(localModulationOrder(llsCfg.pdsch.modulation)), ...
    "TargetCodeRate", double(tx.TargetCodeRate(1)), ...
    "NumLayers", double(tx.PDSCH.NumLayers), ...
    "NumTxPorts", double(llsCfg.pdsch.numberAntennaPorts), ...
    "NumRxAntennas", double(size(rxWaveform,2)), ...
    "SignalEnergyPerOccupiedRE", double(signalEnergyPerOccupiedRE), ...
    "RequestedGridNoiseVariance", double(noiseInfo.GridNoiseVariance), ...
    "MeasuredGridNoiseVariance", double(measuredGridNoiseVariance), ...
    "InterferenceEnabled",logical(interferenceInfo.Enabled), ...
    "InterfererWaveformCount",double(interferenceInfo.WaveformCount), ...
    "ConfiguredDIRdB",double(interferenceInfo.ConfiguredDIRdB), ...
    "MeasuredDIRdB",double(interferenceInfo.MeasuredDIRdB), ...
    "MeasuredPreEqualizationSINRdB",localMeasuredSINR( ...
        channelWaveform,interferenceWaveform,noiseWaveform), ...
    "InterferenceSource",string(interferenceInfo.Source), ...
    "SampleNoiseVariance", double(noiseInfo.SampleNoiseVariance), ...
    "SampleToGridNoiseGain", double(noiseInfo.SampleToGridNoiseVarianceGain), ...
    "FFTSize", double(localFFTSize(tx.OFDM)), ...
    "ActiveSubcarriers", double(tx.Carrier.NSizeGrid*12), ...
    "WaveformSamples", double(size(tx.Waveform,1)), ...
    "ChannelModel", string(llsCfg.channel.model), ...
    "ChannelRealizationSource", string(channelInfo.Source), ...
    "ChannelTransmissionDirection", string(channelInfo.TransmissionDirection), ...
    "TrueChannelGridAvailable", logical(channelInfo.TrueChannelGridAvailable), ...
    "TrueChannelGridVariance", double(sixgr.util.structGet(channelInfo, "TrueChannelGridVariance", 0)), ...
    "TrueChannelGridSHA256", localComplexHash(trueChannelGrid), ...
    "ChannelTimingOffsetSamples", double(channelInfo.TimingOffsetSamples), ...
    "MaximumDopplerHz", double(channelInfo.MaximumDopplerHz), ...
    "NTNEnabled", logical(channelInfo.NTNEnabled), ...
    "NTNProfile", string(channelInfo.NTNProfile), ...
    "NTNOrbitType", string(channelInfo.NTNOrbitType), ...
    "NTNPayloadArchitecture", string(channelInfo.NTNPayloadArchitecture), ...
    "NTNSlantRangeM", double(channelInfo.NTNSlantRangeM), ...
    "NTNPropagationDelaySeconds", double(channelInfo.NTNPropagationDelaySeconds), ...
    "NTNPropagationDelaySamples", double(channelInfo.NTNPropagationDelaySamples), ...
    "NTNPropagationDelayCompensationMode", ...
        string(channelInfo.NTNPropagationDelayCompensationMode), ...
    "NTNPhysicalSatelliteDopplerHz", ...
        double(channelInfo.NTNPhysicalSatelliteDopplerHz), ...
    "NTNMobileMaximumDopplerHz", double(channelInfo.NTNMobileMaximumDopplerHz), ...
    "NTNDopplerCompensationMode", string(channelInfo.NTNDopplerCompensationMode), ...
    "NTNDopplerCompensationHz", double(channelInfo.NTNDopplerCompensationHz), ...
    "NTNResidualSatelliteDopplerHz", ...
        double(channelInfo.NTNResidualSatelliteDopplerHz), ...
    "NTNSampleRateHz", double(channelInfo.NTNSampleRateHz), ...
    "NTNGeometrySource", string(channelInfo.NTNGeometrySource), ...
    "AntennaEnabled", logical(channelInfo.AntennaEnabled), ...
    "AntennaCouplingMode", string(channelInfo.AntennaCouplingMode), ...
    "AntennaTxRole", string(channelInfo.AntennaTxRole), ...
    "AntennaRxRole", string(channelInfo.AntennaRxRole), ...
    "AntennaTxPhysicalElements", double(channelInfo.AntennaTxPhysicalElements), ...
    "AntennaRxPhysicalElements", double(channelInfo.AntennaRxPhysicalElements), ...
    "AntennaTxLogicalPorts", double(channelInfo.AntennaTxLogicalPorts), ...
    "AntennaTxPortToElementSHA256", string(channelInfo.AntennaTxPortToElementSHA256), ...
    "AntennaPatternSource", string(channelInfo.AntennaPatternSource), ...
    "AntennaPhysicalElementChannelApplied", logical(channelInfo.AntennaPhysicalElementChannelApplied), ...
    "AntennaTransmitOrientationDeg", string(mat2str(double(channelInfo.AntennaTransmitOrientationDeg))), ...
    "AntennaReceiveOrientationDeg", string(mat2str(double(channelInfo.AntennaReceiveOrientationDeg))), ...
    "ISACEnabled",isacEnabled, ...
    "ISACSensingExecuted",isacExecuted, ...
    "ISACEvidenceValid",isacEvidenceValid, ...
    "ISACObservationSource",string(sixgr.util.structGet(llsCfg, ...
        "isac.processing.observationSource","disabled")), ...
    "ISACLogicalWaveformSHA256",string(logicalWaveformHash), ...
    "ISACDetectionCount",double(isacDetectionCount), ...
    "ISACMatchedTargetCount",double(isacMatchedTargetCount), ...
    "ISACRangeRMSEM",double(isacRangeRMSE), ...
    "ISACAzimuthRMSEDeg",double(isacAzimuthRMSE), ...
    "ChannelEstimationMode", string(llsCfg.receiver.channelEstimation), ...
    "ChannelEstimateSource", string(rx.ChannelEstimateSource), ...
    "ChannelEstimateEngine", string(rx.ChannelEstimateEngine), ...
    "PostEqSINRdB",double(sixgr.util.structGet(rx,"PostEqSINR_dB",NaN)), ...
    "PostEqSINRPerLayerdB",string(mat2str(double( ...
        sixgr.util.structGet(rx,"PostEqSINRPerLayer_dB",NaN)))), ...
    "PostEqSINRSource",string(sixgr.util.structGet(rx,"PostEqSINRSource","")), ...
    "PostEqSINRValueRole",string(sixgr.util.structGet(rx,"PostEqSINRValueRole","")), ...
    "PostEqSINRValueStatus",string(sixgr.util.structGet(rx,"PostEqSINRValueStatus","")), ...
    "DMRSResidualPostEqSINRBoundEnabled",logical( ...
        llsCfg.receiver.postEqualizationSINR.dmrsResidualBoundEnabled), ...
    "DecisionDirectedPostEqSINRBoundEnabled",logical( ...
        llsCfg.receiver.postEqualizationSINR.decisionDirectedResidualBoundEnabled), ...
    "PostEqSINRDMRSResidualBoundApplied",logical(sixgr.util.structGet( ...
        rx,"PostEqSINRDMRSResidualBoundApplied",false)), ...
    "DecoderNoiseVariance",double(sixgr.util.structGet(rx,"DecoderNoiseVar",NaN)), ...
    "DecoderNoiseVarianceSource",string(sixgr.util.structGet(rx,"DecoderNoiseVarSource","")), ...
    "DecoderNoiseVarianceReductionMethod",string(sixgr.util.structGet( ...
        rx,"DecoderNoiseVarReductionMethod","")), ...
    "DecoderNoiseVarianceConfiguredMode",string( ...
        llsCfg.receiver.decoderNoiseVariance.mode), ...
    "LLRNoiseVariance",double(sixgr.util.structGet(rx,"LLRNoiseVariance",NaN)), ...
    "LLRNoiseVarianceSource",string(sixgr.util.structGet(rx,"LLRNoiseVarianceSource","")), ...
    "LLRNoiseVarianceDomain",string(sixgr.util.structGet(rx,"LLRNoiseVarianceDomain","")), ...
    "Equalizer", string(llsCfg.receiver.equalizer), ...
    "LLRSource", "nrPDSCHDecode_soft_llr", ...
    "LDPCSource", "sixgr_pdsch_actual_ldpc_rate_recovery_decode", ...
    "UseMexLDPC",logical(sixgr.util.structGet(rx.Decode,"UseMexLDPC",false)), ...
    "LDPCDecoderEngine",string(sixgr.util.structGet( ...
        rx.Decode,"DecoderEngine","sixgr.phy.phycode.ldpcDecode")), ...
    "CRCSource", "decoded_transport_block_crc", ...
    "TxProcessChain", "tb_crc_ldpc_rate_match_scramble_qam_layers_precoding_grid_dmrs_ofdm", ...
    "RxProcessChain", localRxProcessChain(perfectEstimation), ...
    "RuntimeSeconds", runtimeSeconds);

diagnostic = struct("Tx",tx,"Rx",rx,"TxInfo",txInfo,"RxInfo",rxInfo, ...
    "NoiseInfo",noiseInfo,"NoiseGridInfo",noiseGridInfo, ...
    "InterferenceInfo",interferenceInfo,"ISAC",isacResult);
if ~logical(runtime.CaptureDiagnostic)
    diagnostic = struct();
end
end

function value = localMeasuredSINR(signal,interference,noise)
value = 10*log10(mean(abs(signal).^2,"all") / ...
    max(mean(abs(interference+noise).^2,"all"),realmin));
end

function applied = localPDSCHHARQCombiningApplied(rx)
applied = false;
decode = sixgr.util.structGet(rx,"Decode",struct());
if isstruct(decode) && isfield(decode,"HARQCombineInfo")
    applied = logical(sixgr.util.structGet(decode.HARQCombineInfo,"Applied",false));
elseif isstruct(decode) && isfield(decode,"Codewords") && iscell(decode.Codewords)
    for index = 1:numel(decode.Codewords)
        info = sixgr.util.structGet(decode.Codewords{index},"HARQCombineInfo",struct());
        applied = applied || logical(sixgr.util.structGet(info,"Applied",false));
    end
end
end

function value = localRxProcessChain(perfectEstimation)
if perfectEstimation
    value = "ofdm_true_channel_oracle_precoder_projection_equalize_soft_llr_rate_recover_ldpc_tb_crc";
else
    value = "ofdm_dmrs_channel_estimate_equalize_soft_llr_rate_recover_ldpc_tb_crc";
end
end

function q = localModulationOrder(modulation)
switch upper(string(modulation))
    case "QPSK"
        q = 2;
    case "16QAM"
        q = 4;
    case "64QAM"
        q = 6;
    case "256QAM"
        q = 8;
    otherwise
        error("sixgr:lls:UnsupportedModulation", ...
            "Unsupported PDSCH modulation %s.", string(modulation));
end
end

function nfft = localFFTSize(info)
nfft = double(sixgr.util.structGet(info, "Nfft", ...
    sixgr.util.structGet(info, "NFFT", NaN)));
end

function digest = localComplexHash(value)
realBytes = typecast(double(real(value(:))), "uint8");
imagBytes = typecast(double(imag(value(:))), "uint8");
digest = sixgr.util.sha256Hex([realBytes(:); imagBytes(:)]);
end
