function array = buildAntennaArray(roleState)
%BUILDANTENNAARRAY Rebuild the phased array bound to an antenna state.
%
% This is the sole runtime constructor for the physical array used by
% antenna plots and auxiliary waveform branches such as ISAC.  The main
% CDL path consumes roleState.ChannelArray because nrCDLChannel requires a
% 38.901 descriptor rather than a phased array System object.

arguments
    roleState (1,1) struct
end

required = ["PolarizationAnglesDeg","ElementFrequencyRangeHz", ...
    "ElementBeamwidthDeg","ElementSidelobeLevelDb", ...
    "ElementMaximumAttenuationDb","ElementMaximumGainDbi", ...
    "PolarizationModel","Size","SpacingWavelength","WavelengthM"];
for index = 1:numel(required)
    if ~isfield(roleState,required(index))
        error("sixgr:lls:IncompleteAntennaState", ...
            "Antenna role state is missing required field %s.",required(index));
    end
end

elements = cell(1,numel(roleState.PolarizationAnglesDeg));
for index = 1:numel(elements)
    elements{index} = phased.NRAntennaElement( ...
        "FrequencyRange",roleState.ElementFrequencyRangeHz, ...
        "PolarizationAngle",roleState.PolarizationAnglesDeg(index), ...
        "PolarizationModel",roleState.PolarizationModel, ...
        "Beamwidth",roleState.ElementBeamwidthDeg, ...
        "SidelobeLevel",roleState.ElementSidelobeLevelDb, ...
        "MaximumAttenuation",roleState.ElementMaximumAttenuationDb, ...
        "MaximumGain",roleState.ElementMaximumGainDbi);
end
array = phased.NRRectangularPanelArray( ...
    "ElementSet",elements,"Size",roleState.Size, ...
    "Spacing",roleState.SpacingWavelength .* roleState.WavelengthM, ...
    "EnablePanelSubarray",false);
end
