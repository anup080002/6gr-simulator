function result = runLLS(configPath, varargin)
%RUNLLS Run a fixed-operating-point, waveform-truth PUSCH link curve.
%
%   RESULT = sixgr.lls.runLLS("configs/lls/pusch_reference.yaml")
%   executes actual transport blocks through the existing production
%   PUSCH transmitter, OFDM waveform, calibrated AWGN, receiver, soft LLR,
%   LDPC decoder, and CRC.  No geometry or BLER abstraction is involved.

ip = inputParser;
ip.FunctionName = "sixgr.lls.runLLS";
ip.addRequired("configPath", @(x) ischar(x) || isstring(x));
ip.addParameter("OutputRoot", "", @(x) ischar(x) || isstring(x));
ip.addParameter("RunTag", "", @(x) ischar(x) || isstring(x));
ip.addParameter("GeneratePlots", [], @(x) isempty(x) || ((islogical(x) || isnumeric(x)) && isscalar(x)));
ip.parse(configPath, varargin{:});
opt = ip.Results;

[cfg, configProvenance] = sixgr.lls.loadConfig(string(configPath));
gitStateAtStart = localGitState();
localEnforceGitPolicy(cfg,gitStateAtStart,"start");
if strlength(strtrim(string(opt.OutputRoot))) > 0
    outputRoot = localResolveOutputRoot(string(opt.OutputRoot));
else
    outputRoot = localResolveOutputRoot(string(cfg.results.outputRoot));
end
generatePlots = logical(cfg.results.generatePlots);
if ~isempty(opt.GeneratePlots)
    generatePlots = logical(opt.GeneratePlots);
end
scenarioId = localSafeToken(string(cfg.scenario.id));
runTag = string(opt.RunTag);
if strlength(strtrim(runTag)) == 0
    runTag = string(datetime("now", "TimeZone", "UTC", "Format", "yyyyMMdd_HHmmss")) + ...
        "_" + extractBefore(configProvenance.ConfigSHA256, 13);
end
runTag = localSafeToken(runTag);
runFolder = fullfile(outputRoot, char(scenarioId), char(runTag));
if exist(runFolder, "dir") == 7
    error("sixgr:lls:OutputAlreadyExists", ...
        "LLS output folder already exists and will not be overwritten: %s", runFolder);
end
mkdir(runFolder);
checkpointFolder = fullfile(runFolder,"checkpoints");
mkdir(checkpointFolder);
localWriteJSON(fullfile(checkpointFolder,"checkpoint_provenance.json"),struct( ...
    "SchemaVersion","sixgr.lls.checkpoint/v1", ...
    "ConfigSHA256",configProvenance.ConfigSHA256, ...
    "ConfigPath",configProvenance.ConfigPath, ...
    "Status","running"));

runClock = tic;
snrDb = double(cfg.simulation.snrDb(:).');
summaryRows = cell(numel(snrDb), 1);
trialTables = cell(numel(snrDb),1);
firstDiagnostic = struct();
fprintf("sixgr.lls: %s | %d SNR points | waveform_truth\n", ...
    char(string(cfg.scenario.id)), numel(snrDb));
for snrIndex = 1:numel(snrDb)
    if logical(cfg.harq.enabled)
        [summaryRows{snrIndex}, trialTables{snrIndex}, diagnostic] = ...
            sixgr.lls.runHARQSNRPoint(cfg,configProvenance.ConfigSHA256,snrIndex);
    elseif logical(cfg.linkAdaptation.enabled)
        [summaryRows{snrIndex}, trialTables{snrIndex}, diagnostic] = ...
            sixgr.lls.runLinkAdaptationSNRPoint( ...
            cfg,configProvenance.ConfigSHA256,snrIndex);
    else
        [summaryRows{snrIndex}, trialTables{snrIndex}, diagnostic] = ...
            sixgr.lls.runSNRPoint(cfg, configProvenance.ConfigSHA256, snrIndex);
    end
    if snrIndex == 1
        firstDiagnostic = diagnostic;
    end
    writetable(struct2table(summaryRows{snrIndex}),fullfile( ...
        checkpointFolder,sprintf("snr_%04d_summary.csv",snrIndex)));
    writetable(trialTables{snrIndex},fullfile( ...
        checkpointFolder,sprintf("snr_%04d_trials.csv",snrIndex)));
    fprintf("  Es/N0=%7.2f dB  TB=%6d  errors=%6d  BLER=%9.4g  CI=[%.4g, %.4g]\n", ...
        summaryRows{snrIndex}.SNRdB, summaryRows{snrIndex}.NumTB, ...
        summaryRows{snrIndex}.NumBlockErrors, summaryRows{snrIndex}.BLER, ...
        summaryRows{snrIndex}.BLERLowerCI, summaryRows{snrIndex}.BLERUpperCI);
end
summaryTable = struct2table(vertcat(summaryRows{:}));
trialTable = vertcat(trialTables{:});
contractTable = sixgr.lls.truthContract(cfg, trialTable);
assumptionsTable = localAssumptionsTable(cfg, trialTable);
requiredSNRTable = sixgr.lls.requiredSNRTable(cfg, summaryTable);
[validityTable, resultValid] = sixgr.lls.validateResults( ...
    cfg, summaryTable, trialTable, contractTable,requiredSNRTable);

writetable(summaryTable, fullfile(runFolder, "bler_vs_snr.csv"));
writetable(trialTable, fullfile(runFolder, "transport_block_trials.csv"));
writetable(assumptionsTable, fullfile(runFolder, "simulation_assumptions.csv"));
writetable(contractTable, fullfile(runFolder, "truth_contract.csv"));
writetable(requiredSNRTable, fullfile(runFolder, "required_snr_at_target_bler.csv"));
writetable(validityTable, fullfile(runFolder, "result_validity.csv"));
localWriteJSON(fullfile(runFolder, "resolved_config.json"), cfg);

plotPaths = strings(0,1);
if generatePlots
    plotPaths(end+1,1) = string(sixgr.lls.plots.plotBLER( ...
        summaryTable, runFolder, cfg.simulation.link));
    plotPaths(end+1,1) = string(sixgr.lls.plots.plotThroughput( ...
        summaryTable, runFolder, cfg.simulation.link));
    plotPaths(end+1,1) = string(sixgr.lls.plots.plotResourceGrid( ...
        firstDiagnostic, runFolder, cfg.simulation.link));
end
ntnPlotPath = sixgr.lls.exportNTNArtifacts( ...
    runFolder, cfg, trialTable, generatePlots);
if strlength(ntnPlotPath) > 0
    plotPaths(end+1,1) = ntnPlotPath;
end
antennaPlotPaths = sixgr.lls.exportAntennaArtifacts( ...
    runFolder,cfg,trialTable,generatePlots);
if ~isempty(antennaPlotPaths)
    plotPaths = [plotPaths;antennaPlotPaths(:)]; %#ok<AGROW>
end
isacPlotPaths = sixgr.lls.exportISACArtifacts( ...
    runFolder,cfg,firstDiagnostic,generatePlots);
if ~isempty(isacPlotPaths)
    plotPaths = [plotPaths;isacPlotPaths(:)]; %#ok<AGROW>
end
runtimeSeconds = toc(runClock);
gitStateAtEnd = localGitState();
localEnforceStableGitState(cfg,gitStateAtStart,gitStateAtEnd);
provenance = struct( ...
    "SchemaVersion", "sixgr.lls.run_provenance/v1", ...
    "ScenarioId", string(cfg.scenario.id), ...
    "ExecutionBackend", "waveform_truth", ...
    "ApproximationMode", "none", ...
    "Source", "sixgr.lls.runLLS", ...
    "ConfigPath", configProvenance.ConfigPath, ...
    "ConfigSourceFiles", configProvenance.SourceFiles, ...
    "ConfigSHA256", configProvenance.ConfigSHA256, ...
    "MasterSeed", double(cfg.simulation.masterSeed), ...
    "StatisticalClass", string(cfg.simulation.statisticalClass), ...
    "MATLABVersion", string(version), ...
    "MATLABRelease", string(version("-release")), ...
    "CreatedUTC", string(datetime("now", "TimeZone", "UTC", "Format", "yyyy-MM-dd'T'HH:mm:ss'Z'")), ...
    "RuntimeSeconds", runtimeSeconds, ...
    "GitCommit", gitStateAtStart.Commit, ...
    "GitWorktreeDirty", gitStateAtStart.WorktreeDirty, ...
    "GitCommitAtEnd", gitStateAtEnd.Commit, ...
    "GitWorktreeDirtyAtEnd", gitStateAtEnd.WorktreeDirty, ...
    "SourceStateStable", gitStateAtStart.Commit == gitStateAtEnd.Commit && ...
        gitStateAtStart.WorktreeDirty == gitStateAtEnd.WorktreeDirty, ...
    "Toolboxes", localToolboxVersions(), ...
    "ResultValidity", string(localValidityStatus(resultValid)), ...
    "ScientificSemanticSHA256", localSemanticHash(summaryTable, trialTable, contractTable));
localWriteJSON(fullfile(runFolder, "run_provenance.json"), provenance);
manifestTable = localArtifactManifest(runFolder);
writetable(manifestTable, fullfile(runFolder, "artifact_manifest.csv"));
localWriteJSON(fullfile(checkpointFolder,"checkpoint_provenance.json"),struct( ...
    "SchemaVersion","sixgr.lls.checkpoint/v1", ...
    "ConfigSHA256",configProvenance.ConfigSHA256, ...
    "ConfigPath",configProvenance.ConfigPath, ...
    "Status",string(localValidityStatus(resultValid)), ...
    "CompletedSNRPoints",height(summaryTable)));

result = struct( ...
    "Status", string(localValidityStatus(resultValid)), ...
    "RunFolder", string(runFolder), ...
    "Config", cfg, ...
    "ConfigSHA256", configProvenance.ConfigSHA256, ...
    "SummaryTable", summaryTable, ...
    "TrialTable", trialTable, ...
    "AssumptionsTable", assumptionsTable, ...
    "TruthContractTable", contractTable, ...
    "RequiredSNRTable", requiredSNRTable, ...
    "ValidityTable", validityTable, ...
    "ArtifactManifest", manifestTable, ...
    "PlotPaths", plotPaths, ...
    "ScientificSemanticSHA256", provenance.ScientificSemanticSHA256, ...
    "RuntimeSeconds", runtimeSeconds);
end

function tableOut = localAssumptionsTable(cfg, trials)
link = upper(string(cfg.simulation.link));
linkCfg = cfg.(lower(char(link)));
if link == "PUSCH" && logical(linkCfg.transformPrecoding)
    waveform = "DFT-s-OFDM";
else
    waveform = "CP-OFDM";
end
mcsTable = sixgr.lls.executedMCSTable(cfg);
if strcmpi(mcsTable,"calibration_explicit")
    mcsIndexSemantics = "zero_based_codeword_index_for_calibration_explicit";
else
    mcsIndexSemantics = "configured_mcs_index";
end
tableOut = table( ...
    string(cfg.scenario.id), string(cfg.simulation.mode), string(cfg.simulation.link), ...
    double(cfg.carrier.frequencyHz), double(cfg.carrier.bandwidthMHz), ...
    double(cfg.carrier.subcarrierSpacingKHz), double(cfg.carrier.nSizeGrid), ...
    double(cfg.allocation.startPRB), double(cfg.allocation.numberPRB), ...
    string(mat2str(double(cfg.allocation.symbols(:).'))), ...
    string(cfg.channel.model), logical(cfg.ntn.enabled), ...
    string(jsonencode(cfg.ntn)),logical(cfg.antenna.enabled), ...
    string(jsonencode(cfg.antenna)),logical(cfg.isac.enabled), ...
    string(jsonencode(cfg.isac)),double(cfg.channel.delaySpreadSeconds), ...
    double(cfg.channel.velocityKmph), double(cfg.channel.txAntennas), ...
    double(cfg.channel.rxAntennas), double(linkCfg.numberLayers), ...
    waveform, string(linkCfg.modulation), ...
    double(trials.TransportBlockSizeBits(1)), double(linkCfg.targetCodeRate), ...
    mcsTable, double(linkCfg.mcsIndex), mcsIndexSemantics, ...
    string(jsonencode(linkCfg.dmrs)), ...
    logical(linkCfg.ptrs.enabled), string(jsonencode(linkCfg.ptrs)), ...
    string(cfg.receiver.channelEstimation), ...
    string(cfg.receiver.equalizer), double(cfg.receiver.ldpcMaxIterations), ...
    logical(cfg.receiver.useMexLDPC), ...
    string(jsonencode(cfg.receiver.postEqualizationSINR)), ...
    string(cfg.receiver.decoderNoiseVariance.mode), ...
    logical(cfg.harq.enabled),string(jsonencode(cfg.harq)), ...
    logical(cfg.interference.enabled),string(jsonencode(cfg.interference)), ...
    logical(cfg.linkAdaptation.enabled),string(jsonencode(cfg.linkAdaptation)), ...
    string(mat2str(double(cfg.simulation.snrDb(:).'))), ...
    double(cfg.simulation.minTransportBlocks), double(cfg.simulation.minBlockErrors), ...
    double(cfg.simulation.maxTransportBlocks), double(cfg.simulation.masterSeed), ...
    string(cfg.simulation.statisticalClass), ...
    "configured_EsN0_per_occupied_QAM_RE", "actual_decoded_TB_CRC", ...
    'VariableNames', { ...
    'ScenarioId','SimulationMode','Link','CarrierFrequencyHz','BandwidthMHz', ...
    'SubcarrierSpacingKHz','CarrierPRBs','StartPRB','AllocatedPRBs', ...
    'SymbolAllocation','ChannelModel','NTNEnabled','NTNConfigurationJSON', ...
    'AntennaEnabled','AntennaConfigurationJSON', ...
    'ISACEnabled','ISACConfigurationJSON', ...
    'DelaySpreadSeconds','VelocityKmph', ...
    'TxAntennas','RxAntennas','Layers','Waveform','Modulation','TBSBits', ...
    'TargetCodeRate','MCSTable','MCSIndex','MCSIndexSemantics', ...
    'DMRSConfigurationJSON','PTRSEnabled','PTRSConfigurationJSON', ...
    'ChannelEstimation','Equalizer','LDPCMaxIterations','UseMexLDPC', ...
    'PostEqualizationSINRPolicyJSON','DecoderNoiseVarianceMode', ...
    'HARQEnabled','HARQConfigurationJSON', ...
    'InterferenceEnabled','InterferenceConfigurationJSON', ...
    'LinkAdaptationEnabled','LinkAdaptationConfigurationJSON','SNRPointsDb', ...
    'MinTransportBlocks','MinBlockErrors','MaxTransportBlocks','MasterSeed','StatisticalClass', ...
    'SNRConvention','BLERDecisionSource'});
end

function digest = localSemanticHash(summaryTable, trialTable, contractTable)
summary = removevars(summaryTable, intersect(summaryTable.Properties.VariableNames, {'RuntimeSeconds'}));
trials = removevars(trialTable, intersect(trialTable.Properties.VariableNames, {'RuntimeSeconds'}));
payload = jsonencode(struct( ...
    "Summary", table2struct(summary), ...
    "Trials", table2struct(trials), ...
    "TruthContract", table2struct(contractTable)));
digest = sixgr.util.sha256Hex(uint8(unicode2native(payload, "UTF-8")));
end

function manifest = localArtifactManifest(folder)
files = dir(fullfile(folder, "*"));
files = files(~[files.isdir]);
rows = repmat(struct("RelativePath","","Bytes",0,"SHA256","","ArtifactType",""), numel(files), 1);
for idx = 1:numel(files)
    path = fullfile(files(idx).folder, files(idx).name);
    [~,~,ext] = fileparts(path);
    rows(idx) = struct( ...
        "RelativePath", string(files(idx).name), ...
        "Bytes", double(files(idx).bytes), ...
        "SHA256", localFileHash(path), ...
        "ArtifactType", upper(erase(string(ext), ".")));
end
manifest = struct2table(rows);
end

function digest = localFileHash(path)
fid = fopen(path, "rb");
if fid < 0
    error("sixgr:lls:ArtifactReadFailed", "Unable to read artifact: %s", path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
bytes = fread(fid, Inf, "*uint8");
digest = sixgr.util.sha256Hex(bytes);
end

function localWriteJSON(path, value)
fid = fopen(path, "w", "n", "UTF-8");
if fid < 0
    error("sixgr:lls:ArtifactWriteFailed", "Unable to write JSON artifact: %s", path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid, "%s", jsonencode(value, "PrettyPrint", true));
end

function commit = localGitCommit()
[status, raw] = system("git rev-parse HEAD");
if status == 0
    commit = string(strtrim(raw));
else
    commit = "unavailable";
end
end

function dirty = localGitDirty()
[status, raw] = system("git status --porcelain");
dirty = status ~= 0 || strlength(strtrim(string(raw))) > 0;
end

function state = localGitState()
state = struct("Commit",localGitCommit(),"WorktreeDirty",localGitDirty());
end

function localEnforceGitPolicy(cfg,state,phase)
requireCommit = logical(cfg.provenance.requireGitCommit);
requireClean = logical(cfg.provenance.requireCleanWorktree);
if requireCommit && (state.Commit == "unavailable" || strlength(state.Commit) ~= 40)
    error("sixgr:lls:GitCommitUnavailable", ...
        "LLS provenance requires an available 40-character Git commit at %s.",phase);
end
if requireClean && state.WorktreeDirty
    error("sixgr:lls:DirtyWorktreeForbidden", ...
        "This LLS configuration requires a clean Git worktree at %s. " + ...
        "Commit or remove all source changes before launching the run.",phase);
end
end

function localEnforceStableGitState(cfg,startState,endState)
if ~logical(cfg.provenance.requireStableSourceThroughoutRun)
    return;
end
localEnforceGitPolicy(cfg,endState,"finalization");
if startState.Commit ~= endState.Commit || ...
        startState.WorktreeDirty ~= endState.WorktreeDirty
    error("sixgr:lls:SourceChangedDuringRun", ...
        "Git source state changed during the LLS run: start commit=%s, " + ...
        "end commit=%s, start dirty=%d, end dirty=%d.", ...
        startState.Commit,endState.Commit,startState.WorktreeDirty,endState.WorktreeDirty);
end
end

function out = localToolboxVersions()
products = ver;
out = struct("Name",{},"Version",{},"Release",{});
for idx = 1:numel(products)
    name = string(products(idx).Name);
    if any(contains(lower(name), ["5g","communications toolbox","matlab"]))
        out(end+1) = struct("Name",name,"Version",string(products(idx).Version), ...
            "Release",string(products(idx).Release)); %#ok<AGROW>
    end
end
end

function value = localValidityStatus(valid)
if valid
    value = "complete_valid";
else
    value = "invalid";
end
end

function root = localResolveOutputRoot(raw)
raw = char(string(raw));
if java.io.File(raw).isAbsolute()
    root = raw;
else
    repoRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
    root = fullfile(repoRoot, raw);
end
if exist(root, "dir") ~= 7
    mkdir(root);
end
root = char(java.io.File(root).getCanonicalPath());
end

function token = localSafeToken(raw)
token = regexprep(string(raw), "[^A-Za-z0-9_.-]", "_");
if strlength(token) == 0
    error("sixgr:lls:InvalidOutputToken", "Scenario/run output token is empty.");
end
end
