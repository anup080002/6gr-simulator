classdef NRAccessMessageCodec
    % Supported TS38.331 V18.8 base access messages, with original UPER bytes.
    % This codec does not assert NAS validity, over-air decoding or activation.
    methods (Static)
        function message=encode(kind,semantic)
            kind=localKind(kind);
            assert(isstruct(semantic) && isscalar(semantic), ...
                'sixgr:rrc:asn1:InvalidAccessSemantic','Use one explicit semantic message.');
            result=sixgr.rrc.asn1.invokeNRAccessCodec("encode", ...
                struct('message_kind',kind,'semantic',semantic));
            message=localResult(kind,result);
        end
        function message=decode(kind,bytes)
            kind=localKind(kind);
            bytes=sixgr.l2.mac.requireMACOctets(bytes);
            assert(~isempty(bytes),'sixgr:rrc:asn1:EmptyAccessMessage','Received UPER must contain actual octets.');
            result=sixgr.rrc.asn1.invokeNRAccessCodec("decode", ...
                struct('message_kind',kind,'uper_hex',localHex(bytes)));
            message=localResult(kind,result);
            assert(isequal(message.Bytes,bytes), ...
                'sixgr:rrc:asn1:AccessOctetsChanged','The decoder must preserve the original complete UPER bytes.');
        end
        function inspection=inspectReceived(kind,bytes)
            kind=localKind(kind);bytes=sixgr.l2.mac.requireMACOctets(bytes);
            assert(~isempty(bytes),'sixgr:rrc:asn1:EmptyAccessMessage','Original UPER must contain octets.');
            result=sixgr.rrc.asn1.invokeNRAccessCodec("inspect_received", ...
                struct('message_kind',kind,'uper_hex',localHex(bytes)));
            id='sixgr:rrc:asn1:AccessCodecProvenanceMismatch';
            assert(result.contract_version=="original_received_RRC_inspection/v1" && ...
                islogical(result.accepted)&&isscalar(result.accepted) && ...
                string(result.message_kind)==kind && string(result.uper_hex)==localHex(bytes) && ...
                result.num_bits==8*numel(bytes) && ...
                string(result.sha256)==string(sixgr.rrc.asn1.asn1SHA256Hex(bytes)),id, ...
                'Retain original received octets, extent, kind and digest.');
            inspection=struct('Accepted',result.accepted,'Status',string(result.status), ...
                'OriginalBytes',bytes,'OriginalSHA256',string(result.sha256), ...
                'RejectionClass',string(result.rejection_class),'RejectionMessage',string(result.rejection_message), ...
                'Codec',string(result.codec),'CodecVersion',string(result.codec_version), ...
                'Profile',string(result.profile),'Decoded',struct(),'PhysicalReceptionProved',false);
            if result.accepted
                decoded=localResult(kind,result.decoded);
                assert(isequal(decoded.Bytes,bytes) && inspection.Status=="received_supported_message_decoded",id, ...
                    'Accepted decoding must retain these exact original bytes.');
                inspection.Decoded=decoded;
            else
                assert(any(inspection.Status==["received_UPER_decode_rejected", ...
                    "received_message_outside_supported_profile","received_noncanonical_or_trailing_octets"]) && ...
                    strlength(inspection.RejectionClass)>0,id,'Only known byte/profile rejections are dispositions.');
            end
        end
    end
end
function kind=localKind(kind)
kind=string(kind);
assert(isscalar(kind) && any(kind==["setup_request","setup","setup_complete", ...
    "security_mode_command","security_mode_complete","security_mode_failure", ...
    "reconfiguration","reconfiguration_complete"]), ...
    'sixgr:rrc:asn1:UnsupportedAccessMessage','The access codec supports only its explicit base messages.');
end
function message=localResult(kind,result)
hex=string(result.uper_hex);
assert(isscalar(hex) && ~isempty(regexp(char(hex),'^(?:[0-9A-F]{2})+$','once')) && ...
    string(result.message_kind)==kind, ...
    'sixgr:rrc:asn1:AccessCodecProvenanceMismatch','Invalid original UPER output.');
bytes=uint8(sscanf(char(hex),'%2x')).';
assert(result.num_bits==8*numel(bytes) && ...
    string(result.sha256)==string(sixgr.rrc.asn1.asn1SHA256Hex(bytes)), ...
    'sixgr:rrc:asn1:AccessCodecProvenanceMismatch','The original octets/hash/length disagree.');
reference="TS_38_331_V18_8_0_base_access_subset";
if any(kind==["security_mode_command","security_mode_complete","security_mode_failure", ...
        "reconfiguration","reconfiguration_complete"])
    reference="TS_38_331_V18_8_0_security_and_new_DRB_subset";
end
message=struct('Kind',kind,'Bytes',bytes,'Bits',reshape(int8(bitget(repmat(bytes(:),1,8),repmat(8:-1:1,numel(bytes),1))).',[],1), ...
    'Hex',hex,'SHA256',string(result.sha256),'Semantic',result.semantic, ...
    'EncodingProfile',string(result.profile),'Codec',string(result.codec), ...
    'CodecVersion',string(result.codec_version),'Reference',reference, ...
    'Scope',string(result.scope),'NASValidated',false,'DedicatedDRBConfigured',false, ...
    'NestedConfiguration',result.nested_configuration,'SecurityActivated',false,'PhysicalReceptionProved',false);
end
function value=localHex(bytes)
value=upper(string(reshape(dec2hex(bytes,2).',1,[])));
end
