function result=validateReceivedRRCSecurity(kind,observation,context,expected,transport)
% Validate original authenticated pending PDCP bytes before Runtime commit.
% transport must come from the stream's private original receiver registry;
% this helper does not certify physical execution from a struct/hash alone.
id='sixgr:rrc:SecurityReceivedBinding';
kind=string(kind);
assert(isscalar(kind)&&any(kind==["security_mode_command","security_mode_complete"]),id,'Original RRC boundary validation failed.');
required(observation,["Status","Token","Payload","PDCPPDUSHA256","RRCPayloadSHA256", ...
    "PDCPCount","AvailableTime_s","UEID","BearerID","Direction","ConfigurationEpoch"],id,'Original RRC boundary validation failed.');
assert(string(observation.Status)=="authenticated_RRC_validation_pending"&& ...
    strlength(string(observation.Token))>0&&isa(observation.Payload,'uint8')&& ...
    isrow(observation.Payload)&&~isempty(observation.Payload),id, ...
    'Only the original Runtime pending integrity-verified payload can reach this adapter.');
required(expected,["ExecutionRunID","ServingCell","RNTI","RRCTransactionID", ...
    "ProtocolConfigurationSHA256"],id,'Original RRC boundary validation failed.');
required(context,["ContextID","UEID","BearerID","Direction","ConfigurationEpoch", ...
    "CipherAlgorithm","IntegrityAlgorithm","SampleRateHz","ClockEpoch","KeySource"],id,'Original RRC boundary validation failed.');
assert(string(context.CipherAlgorithm)=="NEA0"&&string(context.IntegrityAlgorithm)=="128-NIA2"&& ...
    string(context.KeySource)=="configured_preestablished_core_key",id, ...
    'Selected normal-service SRB security needs the explicit staged NEA0/NIA2 context.');
direction="UL";if kind=="security_mode_command",direction="DL";end
assert(string(observation.Direction)==direction&&context.Direction==double(direction=="DL")&& ...
    string(observation.UEID)==string(context.UEID)&&string(observation.BearerID)==string(context.BearerID)&& ...
    observation.ConfigurationEpoch==context.ConfigurationEpoch,id,'Original RRC boundary validation failed.');
required(transport,["ContractVersion","ExecutionRunID","ServingCell","RNTI", ...
    "UEID","BearerID","Direction","ConfigurationEpoch","ProtocolConfigurationSHA256", ...
    "SampleRateHz","ClockEpoch","AvailableAtSample","PDCPPDUSHA256","RRCPayloadSHA256", ...
    "ObservationID","OriginalObservationSHA256"],id,'Original RRC boundary validation failed.');
assert(string(transport.ContractVersion)=="original_shared_SRB1_reception/v1",id,'Original RRC boundary validation failed.');
for name=["ExecutionRunID","ServingCell","RNTI","ProtocolConfigurationSHA256"]
    assert(isequaln(transport.(name),expected.(name)),id,'Original transport scope differs: %s.',name);
end
for name=["UEID","BearerID","ConfigurationEpoch"]
    assert(isequaln(transport.(name),observation.(name)),id,'Original RRC boundary validation failed.');
end
assert(string(transport.Direction)==direction&&transport.SampleRateHz==context.SampleRateHz&& ...
    transport.ClockEpoch==context.ClockEpoch&&strlength(string(transport.ObservationID))>0,id,'Original RRC boundary validation failed.');
sample=observation.AvailableTime_s*context.SampleRateHz;
assert(isscalar(sample)&&isfinite(sample)&&sample>=0&& ...
    abs(sample-round(sample))<=max(1e-7,8*eps(sample))&&transport.AvailableAtSample==round(sample),id,'Original RRC boundary validation failed.');
payloadHash=sixgr.protocol.ProtocolHash.bytes(observation.Payload);
assert(string(observation.RRCPayloadSHA256)==payloadHash&& ...
    string(transport.RRCPayloadSHA256)==payloadHash&& ...
    string(transport.PDCPPDUSHA256)==string(observation.PDCPPDUSHA256),id,'Original RRC boundary validation failed.');
for value=[string(transport.OriginalObservationSHA256),string(transport.PDCPPDUSHA256), ...
        string(expected.ProtocolConfigurationSHA256)]
    assert(~isempty(regexp(char(value),'^[0-9a-f]{64}$','once')),id,'Original RRC boundary validation failed.');
end
message=sixgr.rrc.asn1.NRAccessMessageCodec.decode(kind,observation.Payload);
assert(message.Semantic.transaction_id==expected.RRCTransactionID,id, ...
    'Received RRC transaction must match the original outstanding procedure.');
if kind=="security_mode_command"
    assert(string(message.Semantic.ciphering_algorithm)=="nea0"&& ...
        string(message.Semantic.integrity_algorithm)=="nia2",id,'Original RRC boundary validation failed.');
    purpose="security_command_verified";
else
    purpose="security_complete_verified";
end
receipt=struct('ContractVersion',"validated_RRC_security_boundary/v1", ...
    'ContextID',context.ContextID,'UEID',context.UEID,'BearerID',context.BearerID, ...
    'Direction',context.Direction,'ConfigurationEpoch',context.ConfigurationEpoch, ...
    'Endpoint',"RX",'Purpose',purpose,'RRCTransactionID',message.Semantic.transaction_id, ...
    'RRCPayloadSHA256',payloadHash,'PDCPPDUSHA256',observation.PDCPPDUSHA256, ...
    'PDCPCount',observation.PDCPCount,'OriginalObservationSHA256',transport.OriginalObservationSHA256, ...
    'AtSample',round(sample),'SampleRateHz',context.SampleRateHz,'ClockEpoch',context.ClockEpoch, ...
    'EvidenceBoundary',"original_shared_receiver");
result=struct('OriginalRuntimeToken',observation.Token,'Message',message,'Receipt',receipt, ...
    'OriginalTransport',transport,'SecurityActivated',false,'NASValidated',false);
end
function required(value,names,id,message)
assert(isstruct(value)&&isscalar(value)&&all(isfield(value,names)),id, ...
    message);
end
