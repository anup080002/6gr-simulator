function result=validateSubmittedSecurityComplete(submission,ulContext,dlContext,expected,evidenceBoundary)
% Pure adapter for ORIGINAL PDCP-to-RLC lower-layer submission.
% The private submission owner must authenticate its receipt before calling.
% Queuing an RRC response or observing RF success is not this boundary.
id='sixgr:rrc:SecurityCompleteSubmission';
if nargin<5,evidenceBoundary="original_RRC_submission";end
assert(isscalar(string(evidenceBoundary))&&any(string(evidenceBoundary)==["original_RRC_submission","declared_component"]),id,'Invalid boundary.');
contract="original_PDCP_to_RLC_submission/v1";
if string(evidenceBoundary)=="declared_component",contract="declared_PDCP_to_RLC_submission/v1";end
required={'ContractVersion','ExecutionRunID','UEID','BearerID','ServingCell','RNTI', ...
    'ConfigurationEpoch','ProtocolConfigurationSHA256','SampleRateHz','ClockEpoch', ...
    'PDCPPDU','PDCPCount','SubmittedAtSample','OriginalSubmissionSHA256','SubmissionID'};
assert(isstruct(submission)&&isscalar(submission)&&all(isfield(submission,required)),id,'Original RRC boundary validation failed.');
assert(string(submission.ContractVersion)==contract&& ...
    strlength(string(submission.SubmissionID))>0,id,'Original RRC boundary validation failed.');
if string(evidenceBoundary)=="original_RRC_submission"
    assert(all(isfield(submission,{'TXIntegrityActive','TXCipheringActive','Source','LCID','Direction'}))&& ...
        islogical(submission.TXIntegrityActive)&&isscalar(submission.TXIntegrityActive)&&submission.TXIntegrityActive&& ...
        islogical(submission.TXCipheringActive)&&isscalar(submission.TXCipheringActive)&&~submission.TXCipheringActive&& ...
        string(submission.Source)=="original_RLCEntity_addSDU_handoff"&& ...
        submission.LCID==1&&string(submission.Direction)=="UL",id, ...
        'Original Complete handoff must retain actual active integrity and inactive ciphering.');
end
for name=["ExecutionRunID","ServingCell","RNTI","ProtocolConfigurationSHA256"]
    assert(isequaln(submission.(name),expected.(name)),id,'Original RRC boundary validation failed.');
end
for context={ulContext,dlContext}
    c=context{1};
    assert(string(c.CipherAlgorithm)=="NEA0"&&string(c.IntegrityAlgorithm)=="128-NIA2"&& ...
        string(c.KeySource)=="configured_preestablished_core_key",id,'Original RRC boundary validation failed.');
    for name=["UEID","BearerID","ConfigurationEpoch","SampleRateHz","ClockEpoch"]
        assert(isequaln(submission.(name),c.(name)),id,'Original RRC boundary validation failed.');
    end
end
assert(ulContext.Direction==0&&dlContext.Direction==1&& ...
    isequal(ulContext.IntegrityKey,dlContext.IntegrityKey)&& ...
    isequal(ulContext.CipherKey,dlContext.CipherKey),id,'Original RRC boundary validation failed.');
assert(isa(submission.PDCPPDU,'uint8')&&isrow(submission.PDCPPDU)&& ...
    numel(submission.PDCPPDU)>6&&isnumeric(submission.PDCPCount)&& ...
    isscalar(submission.PDCPCount)&&isfinite(submission.PDCPCount)&& ...
    submission.PDCPCount>=0&&submission.PDCPCount<2^32&& ...
    submission.PDCPCount==fix(submission.PDCPCount),id,'Original RRC boundary validation failed.');
assert(isnumeric(submission.SubmittedAtSample)&&isscalar(submission.SubmittedAtSample)&& ...
    isfinite(submission.SubmittedAtSample)&&submission.SubmittedAtSample>=0&& ...
    submission.SubmittedAtSample==fix(submission.SubmittedAtSample)&& ...
    ~isempty(regexp(char(submission.OriginalSubmissionSHA256),'^[0-9a-f]{64}$','once')),id,'Original RRC boundary validation failed.');
header=sixgr.l2.pdcp18.PDCPHeaderCodec.decode('SRB',12,submission.PDCPPDU);
assert(header.SN==mod(submission.PDCPCount,4096)&&numel(header.Payload)>4,id,'Original RRC boundary validation failed.');
payload=header.Payload(1:end-4);
message=sixgr.rrc.asn1.NRAccessMessageCodec.decode('security_mode_complete',payload);
assert(message.Semantic.transaction_id==expected.RRCTransactionID,id,'Original RRC boundary validation failed.');
mac=sixgr.l2.pdcp18.PDCPSecurity128.nia2(ulContext.IntegrityKey, ...
    submission.PDCPCount,0,0,submission.PDCPPDU(1:end-4),8*(numel(submission.PDCPPDU)-4));
assert(isequal(submission.PDCPPDU(end-3:end),mac),id, ...
    'Original Complete must be integrity-protected and unciphered.');
tx=boundary(ulContext,"TX");rx=boundary(dlContext,"RX");
result=struct('Message',message,'TXReceipt',tx,'RXReceipt',rx, ...
    'OriginalSubmissionID',submission.SubmissionID,'SecurityActivated',false);
    function r=boundary(c,endpoint)
        r=struct('ContractVersion',"validated_RRC_security_boundary/v1", ...
            'ContextID',c.ContextID,'UEID',c.UEID,'BearerID',c.BearerID, ...
            'Direction',c.Direction,'ConfigurationEpoch',c.ConfigurationEpoch, ...
            'Endpoint',endpoint,'Purpose',"security_complete_submitted", ...
            'RRCTransactionID',message.Semantic.transaction_id, ...
            'RRCPayloadSHA256',sixgr.protocol.ProtocolHash.bytes(payload), ...
            'PDCPPDUSHA256',sixgr.protocol.ProtocolHash.bytes(submission.PDCPPDU), ...
            'PDCPCount',submission.PDCPCount, ...
            'OriginalObservationSHA256',submission.OriginalSubmissionSHA256, ...
            'AtSample',submission.SubmittedAtSample,'SampleRateHz',c.SampleRateHz, ...
            'ClockEpoch',c.ClockEpoch,'EvidenceBoundary',string(evidenceBoundary));
    end
end
