function result = applyNetworkCompensation(profile, rhoHat, epsilonHat, fUlHz, commonFrequencyHz)
%APPLYNETWORKCOMPENSATION Apply the selected, versioned UL correction rule.

rule = sixgr.ntn.resilientsync.state.selectUlCoefficientRule(profile, fUlHz);
correctionHz = -double(fUlHz) * (rule.FDDScaling * rule.KRho * double(rhoHat) + ...
    rule.KEpsilon * double(epsilonHat)) + double(commonFrequencyHz);
result = struct("FrequencyCorrection_Hz", correctionHz, ...
    "CoefficientRuleId", rule.CoefficientRuleId, ...
    "StateVersion", rule.StateVersion, "ProfileId", rule.ProfileId, ...
    "AppliedOnce", true,"EffectiveKRho",rule.FDDScaling*rule.KRho, ...
    "EffectiveKEpsilon",rule.KEpsilon);
end
