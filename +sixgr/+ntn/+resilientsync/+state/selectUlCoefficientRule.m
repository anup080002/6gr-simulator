function rule = selectUlCoefficientRule(profile, fUlHz)
%SELECTULCOEFFICIENTRULE Resolve the state-owned UL frequency rule.

sixgr.ntn.resilientsync.state.validateCompensationStateProfile(profile);
rule = struct("ProfileId", string(profile.id), ...
    "CoefficientRuleId", string(profile.coefficient_rule_id), ...
    "KRho", double(profile.k_rho), "KEpsilon", double(profile.k_epsilon), ...
    "FDDScaling", double(profile.fdd_scaling), "ULCarrier_Hz", double(fUlHz), ...
    "StateVersion", double(profile.state_version));
end
