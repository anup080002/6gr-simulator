function proposalTable = buildTraceabilityReport(runDirectory, scenario)
%BUILDTRACEABILITYREPORT Emit figure and TDoc-proposal traceability.
%
% Figure_Traceability_SixGR_NTN.csv is the immutable figure contract.  The
% TDoc specification separately requires Proposal 1--15 traceability; do
% not substitute the figure map for that proposal/evidence binding.

figureTable=localFigureTraceability(runDirectory,scenario);
writetable(figureTable,fullfile(char(runDirectory),'figure_traceability_matrix.csv'));

spec={ ...
 1,'common deltaTauSL, eT and eF','A','ANALYTICAL|MONTE_CARLO_GEOMETRY', ...
   {'tables/gnss_degraded_holdover.csv','tables/reference_area_summary.csv'}; ...
 2,'scenario and configuration report','CONFIG','ARCHITECTURE_DIAGRAM', ...
   {'config/executed_campaign.yaml','config/resolved_config.json','config/state_profiles.yaml'}; ...
 3,'two-stage acquisition and ordinary-uplink correction','C|D','CALIBRATED_LLS', ...
   {'tables/prach_residual_summary.csv','tables/pusch_residual_summary.csv','tables/pucch_residual_summary.csv'}; ...
 4,'feeder validity and compensation state profiles','A|B','ANALYTICAL|ARCHITECTURE_DIAGRAM', ...
   {'tables/feeder_polynomial_summary.csv','tables/compensation_state_matrix.csv'}; ...
 5,'k_offset hierarchy','E','SCHEDULER_SYSTEM', ...
   {'tables/k_offset_samples.csv','tables/k_offset_summary.csv'}; ...
 6,'TA reporting and HD-FDD procedure','F','EVENT_PROCEDURE', ...
   {'tables/ta_report_events.csv','tables/ta_report_summary.csv'}; ...
 7,'network compensation-state profile','B','ARCHITECTURE_DIAGRAM', ...
   {'tables/compensation_state_matrix.csv'}; ...
 8,'state-aware estimator and mismatch handling','B','ANALYTICAL|CALIBRATED_LLS|EVENT_PROCEDURE', ...
   {'tables/estimator_reference.csv','tables/mismatch_classifier.csv','tables/network_action_outcomes.csv'}; ...
 9,'PRACH search and false-alarm calibration','C','CALIBRATED_LLS', ...
   {'tables/prach_false_alarm_calibration.csv','tables/prach_frequency_offset_sweep.csv'}; ...
 10,'timing pipeline','E','SCHEDULER_SYSTEM', ...
   {'tables/timing_pipeline.csv'}; ...
 11,'TA knowledge and report granularity','F','EVENT_PROCEDURE', ...
   {'tables/ta_report_events.csv','tables/ta_report_summary.csv'}; ...
 12,'residual impairment response','D','ANALYTICAL|CALIBRATED_LLS', ...
   {'tables/pusch_residual_summary.csv','tables/pucch_residual_summary.csv'}; ...
 13,'PRACH correction and RAR timing','C','CALIBRATED_LLS', ...
   {'tables/prach_timing_offset_sweep.csv','tables/prach_multi_occasion_trials.csv'}; ...
 14,'mixed population and transition events','G','EVENT_PROCEDURE', ...
   {'tables/mixed_population.csv','tables/transition_events.csv'}; ...
 15,'all-campaign evidence contract','A|B|C|D|E|F|G','MULTI_CLASS', ...
   {'acceptance/evidence_registry.csv','raw/campaign_a_checkpoint.mat','raw/campaign_b_checkpoint.mat', ...
    'raw/campaign_c_checkpoint.mat','raw/campaign_d_checkpoint.mat','raw/campaign_e_checkpoint.mat', ...
    'raw/campaign_f_checkpoint.mat','raw/campaign_g_checkpoint.mat'}};

rows=cell(size(spec,1),1);
for index=1:size(spec,1)
    paths=string(spec{index,5}(:));missing=strings(0,1);
    for artifactIndex=1:numel(paths)
        path=fullfile(char(runDirectory),char(replace(paths(artifactIndex),"/",filesep)));
        if ~isfile(path),missing(end+1,1)=paths(artifactIndex);end %#ok<AGROW>
    end
    if isempty(missing),status="PRODUCED";else,status="MISSING";end
    rows{index}={double(spec{index,1}),string(spec{index,2}),string(spec{index,3}), ...
        string(spec{index,4}),strjoin(paths,"|"),numel(paths),status,strjoin(missing,"|"), ...
        string(scenario.ConfigSHA256)};
end
proposalTable=cell2table(vertcat(rows{:}),'VariableNames', ...
    {'ProposalId','Requirement','CampaignBinding','EvidenceClasses','ArtifactPaths', ...
    'ArtifactCount','Status','MissingArtifacts','ConfigSHA256'});
proposalTable.Properties.VariableUnits=repmat({''},1,width(proposalTable));
writetable(proposalTable,fullfile(char(runDirectory),'traceability_matrix.csv'));
end

function T=localFigureTraceability(runDirectory,scenario)
source=string(scenario.outputs.figure_traceability_file);
if exist(source,'file')~=2
    root=fileparts(fileparts(fileparts(fileparts(fileparts(mfilename('fullpath'))))));
    source=fullfile(root,char(source));
end
T=readtable(source,'TextType','string');
T.Status=strings(height(T),1);T.OutputPath=strings(height(T),1);T.PNG_SHA256=strings(height(T),1);
for index=1:height(T)
    if T.Figure(index)=="2-11"
        T.Status(index)="INTENTIONAL_NUMBERING_GAP";continue;
    end
    if T.Pack(index)=="TDoc",directory=string(scenario.outputs.public_dir);else,directory=string(scenario.outputs.confidential_dir);end
    path=fullfile(char(runDirectory),char(directory),char(T.Output_Basename(index)+".png"));
    if exist(path,'file')~=2
        T.Status(index)="MISSING";continue;
    end
    T.Status(index)="PRODUCED";
    T.OutputPath(index)=replace(string(path),string(runDirectory)+filesep,"");
    fid=fopen(path,'rb');cleanup=onCleanup(@() fclose(fid));bytes=fread(fid,Inf,'*uint8');clear cleanup
    T.PNG_SHA256(index)=sixgr.util.sha256Hex(bytes);
end
end
