function manifest = buildManifest(runDirectory, scenario, acceptanceStatus, evidenceTable)
%BUILDMANIFEST Build the complete hash-addressed run manifest.

files = dir(fullfile(char(runDirectory),"**","*"));
files = files(~[files.isdir]);
% A manifest cannot truthfully contain the hash of the file that is being
% overwritten.  Exclude it so finalization is repeatable and self-consistent.
files = files(~strcmpi(string({files.name}),"manifest.json"));
relative = strings(numel(files),1); sha = strings(numel(files),1);
bytes = zeros(numel(files),1); modified = strings(numel(files),1);
for index = 1:numel(files)
    path = fullfile(files(index).folder,files(index).name);
    relative(index) = string(strrep(path,[char(runDirectory) filesep],""));
    relative(index) = replace(relative(index),"\","/");
    bytes(index) = double(files(index).bytes);
    modified(index) = string(datetime(files(index).datenum,"ConvertFrom","datenum", ...
        "TimeZone","UTC","Format","yyyy-MM-dd'T'HH:mm:ss'Z'"));
    fid = fopen(path,"rb");
    if fid < 0
        error("sixgr:ntn:resilientsync:ManifestReadFailed", ...
            "Cannot hash artifact %s.",path);
    end
    cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
    data = fread(fid,Inf,"*uint8");
    clear cleanup
    sha(index) = sixgr.util.sha256Hex(data);
end
artifactTable = table(relative,bytes,sha,modified, ...
    'VariableNames',{'Path','Bytes','SHA256','ModifiedUTC'});
manifest = struct( ...
    "SchemaVersion","sixgr.ntn.resilientsync.manifest/v1", ...
    "RunId",string(scenario.RunId), ...
    "CreatedUTC",string(datetime("now","TimeZone","UTC", ...
        "Format","yyyy-MM-dd'T'HH:mm:ss'Z'")), ...
    "Git",localGit(),"MATLAB",localMATLAB(),"Host",localHost(), ...
    "ConfigPath",string(scenario.ConfigPath), ...
    "ConfigSourceFiles",string(scenario.ConfigSourceFiles), ...
    "ConfigSHA256",string(scenario.ConfigSHA256), ...
    "StateProfilesPath",string(scenario.StateProfilesPath), ...
    "StateProfileSHA256",string(scenario.StateProfileSHA256), ...
    "Seeds",double(scenario.seed),"RunMode",string(scenario.run_mode), ...
    "ProvenanceClasses",unique(string(evidenceTable.EvidenceClass)), ...
    "Measured",any(logical(evidenceTable.Measured)), ...
    "AcceptanceStatus",string(acceptanceStatus), ...
    "Evidence",table2struct(evidenceTable), ...
    "Artifacts",table2struct(artifactTable));
path = fullfile(char(runDirectory),"manifest.json");
fid = fopen(path,"w","n","UTF-8");
if fid < 0, error("sixgr:ntn:resilientsync:ManifestWriteFailed","Cannot write manifest."); end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,"%s\n",jsonencode(manifest,"PrettyPrint",true));
end

function state = localGit()
[s1,commit] = system("git rev-parse HEAD");
[s2,status] = system("git status --porcelain");
state = struct("Commit",string(strtrim(commit)), ...
    "WorktreeDirty",s2 ~= 0 || strlength(strtrim(string(status))) > 0, ...
    "Available",s1 == 0);
end

function out = localMATLAB()
v = ver;
out = struct("Version",string(version),"Release",string(version("-release")), ...
    "Toolboxes",struct("Name",string({v.Name}),"Version",string({v.Version})));
end

function out = localHost()
out = struct("Computer",string(computer),"Hostname",string(getenv("COMPUTERNAME")), ...
    "Username",string(getenv("USERNAME")));
end
