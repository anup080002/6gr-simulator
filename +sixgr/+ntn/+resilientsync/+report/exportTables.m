function records = exportTables(runDirectory,scenario,tables,acceptance)
%EXPORTTABLES Emit the complete numbered TDoc table contract.

scenarioTable=table(string(scenario.campaign_name),string(scenario.run_mode),double(scenario.seed), ...
    double(scenario.geometry.earth_radius_km),double(scenario.geometry.orbit.altitude_km), ...
    double(scenario.geometry.timing_mapping.kappa_t),string(scenario.ConfigSHA256), ...
    'VariableNames',{'Campaign','RunMode','Seed','EarthRadius_km','OrbitAltitude_km','KappaT','ConfigSHA256'});
scenarioTable.Properties.VariableUnits={'','','','km','km','',''};
carrierTable=struct2table(scenario.carriers);
carrierTable.Properties.VariableUnits=repmat({''},1,width(carrierTable));
for n={'f_dl_hz','f_ul_hz'},if ismember(n{1},carrierTable.Properties.VariableNames),carrierTable.Properties.VariableUnits{n{1}}='Hz';end,end
residualTable=localResidualGrid(scenario);
correctionTable=localCorrection(scenario);
kConfig=localKConfig(scenario);
taTriggers=table(string(scenario.ta_report.triggers(:)), ...
    repmat("YAML_CONFIG",numel(scenario.ta_report.triggers),1), ...
    'VariableNames',{'Trigger','Source'});
phyAssumptions=table(string(scenario.physical_layer.prach_backend), ...
    string(scenario.physical_layer.pusch_backend),string(scenario.physical_layer.pucch_backend), ...
    logical(scenario.physical_layer.require_calibrated_ntn_channel_for_measured_claim), ...
    logical(scenario.physical_layer.permit_proxy),double(scenario.physical_layer.confidence_level), ...
    'VariableNames',{'PRACHBackend','PUSCHBackend','PUCCHBackend', ...
    'RequireCalibratedNTN','PermitProxy','ConfidenceLevel'});
phyAssumptions.Properties.VariableUnits={'','','','','','1'};

spec={ ...
 1,'scenario_assumptions',scenarioTable,'ARCHITECTURE_DIAGRAM'; ...
 2,'carrier_cases',carrierTable,'ARCHITECTURE_DIAGRAM'; ...
 3,'compensation_profiles',tables.compensation_state_matrix,'ARCHITECTURE_DIAGRAM'; ...
 4,'gnss_degraded_holdover',tables.gnss_degraded_holdover,'ANALYTICAL'; ...
 5,'reference_area_timing',tables.reference_area_summary(:,{'ReferenceAreaRadius_m','Elevation_deg','P95AbsoluteDeltaTauSL_s','P95AbsoluteULRPArrivalError_s'}),'MONTE_CARLO_GEOMETRY'; ...
 6,'reference_area_frequency',tables.reference_area_summary(:,{'ReferenceAreaRadius_m','Elevation_deg','P95AbsoluteDifferentialCFO_SBand_Hz','P95AbsoluteDifferentialCFO_Ka_Hz'}),'MONTE_CARLO_GEOMETRY'; ...
 7,'feeder_polynomial',tables.feeder_polynomial_summary,'ANALYTICAL'; ...
 8,'estimator_reference',tables.estimator_reference,'ANALYTICAL'; ...
 9,'residual_grid',residualTable,'ARCHITECTURE_DIAGRAM'; ...
 10,'prach_calibration',tables.prach_false_alarm_calibration,'CALIBRATED_LLS'; ...
 11,'correction_command',correctionTable,'ARCHITECTURE_DIAGRAM'; ...
 12,'koffset_configuration',kConfig,'ARCHITECTURE_DIAGRAM'; ...
 13,'koffset_results',tables.k_offset_summary,'SCHEDULER_SYSTEM'; ...
 14,'timing_pipeline',tables.timing_pipeline,'SCHEDULER_SYSTEM'; ...
 15,'ta_triggers',taTriggers,'ARCHITECTURE_DIAGRAM'; ...
 18,'physical_layer_assumptions',phyAssumptions,'ARCHITECTURE_DIAGRAM'; ...
 19,'pusch_residual',tables.pusch_residual_summary,'CALIBRATED_LLS'; ...
 20,'pucch_residual',tables.pucch_residual_summary,'CALIBRATED_LLS'; ...
 21,'trs_measurement',tables.trs_frequency_offset_sweep,'CALIBRATED_LLS'; ...
 22,'acquisition_search',tables.prach_frequency_offset_sweep,'CALIBRATED_LLS'; ...
 23,'ta_reporting',tables.ta_report_summary,'EVENT_PROCEDURE'; ...
 24,'hd_fdd_events',tables.ta_report_events(tables.ta_report_events.DuplexMode=="HD_FDD",:),'EVENT_PROCEDURE'; ...
 25,'mixed_population',tables.mixed_population,'EVENT_PROCEDURE'; ...
 26,'transition_events',tables.transition_events,'EVENT_PROCEDURE'; ...
 27,'acceptance_checks',acceptance,'EVENT_PROCEDURE'; ...
 28,'evidence_provenance',localEvidenceSummary(tables),'ARCHITECTURE_DIAGRAM'};
records=table();
for index=1:size(spec,1)
    number=double(spec{index,1});slug=string(spec{index,2});T=spec{index,3};evidence=string(spec{index,4});
    base="tables/numbered/table_"+compose('%02d',number)+"_"+slug;
    meta=struct('TableNumber',number,'Title',slug,'ConfigSHA256',string(scenario.ConfigSHA256), ...
        'StateProfileSHA256',string(scenario.StateProfileSHA256),'Provenance',evidence);
    rec=sixgr.ntn.resilientsync.report.saveResultArtifact(runDirectory,base,T,evidence,meta);
    localWriteTSV(fullfile(char(runDirectory),char(base+".tsv")),T);
    localWriteMarkdown(fullfile(char(runDirectory),char(base+".md")),T,"Table "+number+": "+slug);
    records=[records;rec]; %#ok<AGROW>
end
end

function T=localResidualGrid(cfg)
[timing,frequency]=ndgrid(double(cfg.residual_grid.timing_error_us(:)), ...
    double(cfg.residual_grid.frequency_error_khz(:)));
T=table(timing(:),frequency(:),timing(:)*1e-6,frequency(:)*1e3, ...
    repmat("YAML_CONFIG",numel(timing),1), ...
    'VariableNames',{'TimingError_us','FrequencyError_kHz','TimingError_s','FrequencyError_Hz','Source'});
T.Properties.VariableUnits={'us','kHz','s','Hz',''};
end
function T=localCorrection(cfg)
[tr,ts,fr,fs]=ndgrid(double(cfg.correction.timing_range_us(:)), ...
    double(cfg.correction.timing_step_us(:)),double(cfg.correction.frequency_range_khz(:)), ...
    double(cfg.correction.frequency_step_hz(:)));
T=table(tr(:),ts(:),fr(:),fs(:),repmat("YAML_CONFIG",numel(tr),1), ...
    'VariableNames',{'TimingRange_us','TimingStep_us','FrequencyRange_kHz','FrequencyStep_Hz','Source'});
T.Properties.VariableUnits={'us','us','kHz','Hz',''};
end
function T=localKConfig(cfg)
[e,s]=ndgrid(double(cfg.k_offset.beam_center_elevations_deg(:)),double(cfg.k_offset.scs_khz(:)));
T=table(e(:),s(:),repmat(double(cfg.k_offset.beam_diameter_km),numel(e),1), ...
    repmat(double(cfg.k_offset.ue_drops_per_beam),numel(e),1), ...
    repmat(string(cfg.k_offset.ue_distribution),numel(e),1), ...
    'VariableNames',{'Elevation_deg','SCS_kHz','BeamDiameter_km','UEDrops','Distribution'});
T.Properties.VariableUnits={'deg','kHz','km','',''};
end
function T=localEvidenceSummary(tables)
names=string(fieldnames(tables));rows=zeros(numel(names),1);columns=zeros(numel(names),1);provenance=strings(numel(names),1);
for i=1:numel(names),value=tables.(names(i));rows(i)=height(value);columns(i)=width(value);if ismember('Provenance',value.Properties.VariableNames),p=unique(string(value.Provenance));provenance(i)=strjoin(p,'|');else,provenance(i)='derived_from_named_campaign_table';end,end
T=table(names,rows,columns,provenance,'VariableNames',{'Artifact','Rows','Columns','Provenance'});
T.Properties.VariableUnits={'','','',''};
end
function localWriteTSV(path,T)
writetable(T,path,'Delimiter','\t','FileType','text');
end
function localWriteMarkdown(path,T,titleText)
fid=fopen(path,'w','n','UTF-8');if fid<0,error('sixgr:ntn:resilientsync:TableWriteFailed','Unable to write %s.',path);end
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'# %s\n\n',char(titleText));names=string(T.Properties.VariableNames);
fprintf(fid,'| %s |\n',char(strjoin(names,' | ')));fprintf(fid,'|%s|\n',repmat(' --- |',1,numel(names)));
for r=1:height(T)
    values=strings(1,width(T));
    for c=1:width(T)
        values(c)=replace(localMarkdownValue(T{r,c}),'|','\|');
    end
    fprintf(fid,'| %s |\n',char(strjoin(values,' | ')));
end
end

function out=localMarkdownValue(value)
% A table cell can legally contain a nonscalar numeric array or a nested
% scalar cell.  Markdown is a presentation companion; preserve the value
% in one deterministic cell instead of relying on scalar string assignment.
while iscell(value) && isscalar(value)
    value=value{1};
end
if isempty(value)
    out="";
elseif isnumeric(value) || islogical(value)
    if isscalar(value),out=string(value);else,out=string(mat2str(value));end
elseif ischar(value)
    out=string(value);
elseif isstring(value) || iscategorical(value) || isdatetime(value) || isduration(value)
    out=strjoin(string(value(:)).',";");
elseif isstruct(value)
    out=string(jsonencode(value));
elseif iscell(value)
    parts=strings(numel(value),1);
    for index=1:numel(value),parts(index)=localMarkdownValue(value{index});end
    out=strjoin(parts.',";");
else
    out=string(jsonencode(value));
end
end
