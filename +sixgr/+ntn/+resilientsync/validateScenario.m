function scenario = validateScenario(scenario)
%VALIDATESCENARIO Fail closed on incomplete resilient-NTN campaign input.

required = [ ...
    "schema_version","campaign_name","run_mode","seed", ...
    "provenance.require_truth_contract","geometry.earth_radius_km", ...
    "geometry.earth_rotation_rate_rad_s", ...
    "geometry.orbit.type","geometry.orbit.altitude_km", ...
    "geometry.timing_mapping.kappa_t","carriers", ...
    "gnss_degraded.speeds_kmh","gnss_degraded.ages_s", ...
    "gnss_free.reference_area_radii_km","gnss_free.elevations_deg", ...
    "gnss_free.drops_per_point","physical_layer.pfa_total", ...
    "public_figures.baseline_elevation_deg", ...
    "public_figures.holdover_motion_projection_deg", ...
    "public_figures.timing_cdf_radii_km", ...
    "public_figures.estimator.timing_sigma_us", ...
    "public_figures.search_threshold.hypotheses", ...
    "public_figures.residual_cfo.normalized_grid", ...
    "state_profiles.enabled","outputs.output_root", ...
    "ntn_topology.enabled","ntn_topology.geometry_model", ...
    "ntn_topology.epoch_utc","ntn_topology.duration_s", ...
    "ntn_topology.sample_time_s","ntn_topology.access.minimum_elevation_deg", ...
    "ntn_topology.satellite.altitude_m", ...
    "ntn_topology.satellite.antenna_binding", ...
    "ntn_topology.service_ue.antenna_binding", ...
    "ntn_topology.link_budget.carrier_frequency_hz", ...
    "ntn_topology.link_budget.bandwidth_hz", ...
    "physical_layer.topology_proof_pdsch_config"];
for path = required
    value = sixgr.util.structGet(scenario, path, []);
    if isempty(value)
        error("sixgr:ntn:resilientsync:MissingConfig", ...
            "Resolved campaign is missing required YAML value %s.", char(path));
    end
end

mode = lower(string(scenario.run_mode));
if ~ismember(mode, ["quick","tdoc","filing"])
    error("sixgr:ntn:resilientsync:InvalidRunMode", ...
        "run_mode must be quick, tdoc, or filing; got %s.", char(mode));
end
scenario.run_mode = char(mode);
if string(scenario.geometry.orbit.type) ~= "circular_leo"
    error("sixgr:ntn:resilientsync:UnsupportedOrbit", ...
        "Only the explicitly configured circular_leo analytical orbit is supported.");
end
localPositiveScalar(scenario.geometry.earth_radius_km, "geometry.earth_radius_km");
localPositiveScalar(scenario.geometry.earth_rotation_rate_rad_s, ...
    "geometry.earth_rotation_rate_rad_s");
localPositiveScalar(scenario.geometry.orbit.altitude_km, "geometry.orbit.altitude_km");
localPositiveScalar(scenario.geometry.speed_of_light_m_s, "geometry.speed_of_light_m_s");
localPositiveScalar(scenario.gnss_free.drops_per_point, "gnss_free.drops_per_point");
localPositiveScalar(scenario.k_offset.ue_drops_per_beam, "k_offset.ue_drops_per_beam");
if abs(double(scenario.geometry.timing_mapping.kappa_t) - 2) > eps
    error("sixgr:ntn:resilientsync:UnsupportedTimingMapping", ...
        "The baseline campaign requires geometry.timing_mapping.kappa_t=2.");
end
if string(scenario.gnss_free.distribution) ~= "uniform_in_area"
    error("sixgr:ntn:resilientsync:InvalidDropDistribution", ...
        "GNSS-free reference-area drops must use uniform_in_area.");
end
if string(scenario.gnss_free.geometry) ~= "exact_spherical_earth"
    error("sixgr:ntn:resilientsync:InvalidGeometry", ...
        "GNSS-free geometry must use exact_spherical_earth.");
end
if logical(scenario.physical_layer.permit_proxy)
    error("sixgr:ntn:resilientsync:ProxyForbidden", ...
        "Resilient synchronization publication campaigns prohibit proxy PHY evidence.");
end
if abs(double(scenario.gnss_degraded.service_link_elevation_deg)- ...
        double(scenario.public_figures.holdover_motion_projection_deg))>eps
    error("sixgr:ntn:resilientsync:HoldoverProjectionMismatch", ...
        ["gnss_degraded.service_link_elevation_deg and " ...
         "public_figures.holdover_motion_projection_deg must match."]);
end
if ~logical(scenario.outputs.save_fig) || ...
        ~logical(scenario.outputs.save_pdf_vector) || ...
        double(scenario.outputs.save_png_dpi)~=300
    error("sixgr:ntn:resilientsync:PublicFigureFormatContract", ...
        "Public NTN figures require FIG, vector PDF, and 300-dpi PNG output.");
end
normalized=double(scenario.public_figures.residual_cfo.normalized_grid(:));
if isempty(normalized) || any(~isfinite(normalized)) || ...
        any(normalized<0|normalized>0.4) || any(diff(normalized)<=0)
    error("sixgr:ntn:resilientsync:InvalidNormalizedCFOGrid", ...
        "public_figures.residual_cfo.normalized_grid must increase from 0 to at most 0.4.");
end
if ~logical(scenario.ntn_topology.enabled)
    error("sixgr:ntn:resilientsync:TopologyDisabled", ...
        "The resilient NTN campaign requires ntn_topology.enabled=true.");
end
if string(scenario.ntn_topology.geometry_model) ~= ...
        "exact_spherical_earth_circular_two_body"
    error("sixgr:ntn:resilientsync:UnsupportedTopologyGeometry", ...
        "ntn_topology.geometry_model must be exact_spherical_earth_circular_two_body.");
end
localPositiveScalar(scenario.ntn_topology.duration_s,"ntn_topology.duration_s");
localPositiveScalar(scenario.ntn_topology.sample_time_s,"ntn_topology.sample_time_s");
localPositiveScalar(scenario.ntn_topology.satellite.altitude_m, ...
    "ntn_topology.satellite.altitude_m");
localPositiveScalar(scenario.ntn_topology.link_budget.carrier_frequency_hz, ...
    "ntn_topology.link_budget.carrier_frequency_hz");
localPositiveScalar(scenario.ntn_topology.link_budget.bandwidth_hz, ...
    "ntn_topology.link_budget.bandwidth_hz");
minimumElevation = double(scenario.ntn_topology.access.minimum_elevation_deg);
if ~isscalar(minimumElevation) || ~isfinite(minimumElevation) || ...
        minimumElevation < 0 || minimumElevation >= 90
    error("sixgr:ntn:resilientsync:InvalidMinimumElevation", ...
        "ntn_topology.access.minimum_elevation_deg must be in [0,90).");
end
if mode ~= "quick" && double(scenario.gnss_free.drops_per_point) < 300000
    error("sixgr:ntn:resilientsync:InsufficientGeometryDrops", ...
        "TDoc and filing modes require at least 300000 geometry drops per point.");
end
if mode ~= "quick" && double(scenario.physical_layer.prach_trials_min) < 10000
    error("sixgr:ntn:resilientsync:InsufficientPRACHTrials", ...
        "TDoc and filing modes require at least 10000 PRACH trials.");
end
for index = 1:numel(scenario.StateProfiles)
    sixgr.ntn.resilientsync.state.validateCompensationStateProfile(scenario.StateProfiles(index));
end
end

function localPositiveScalar(value, path)
if ~(isnumeric(value) && isscalar(value) && isfinite(value) && value > 0)
    error("sixgr:ntn:resilientsync:InvalidConfigValue", ...
        "%s must be a finite positive scalar.", char(path));
end
end
