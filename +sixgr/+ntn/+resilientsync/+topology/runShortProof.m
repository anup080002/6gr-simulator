function result = runShortProof(configPath,varargin)
%RUNSHORTPROOF Execute topology, link budget and one physical PDSCH point.
%
% This is a short integration proof, not a publication BLER campaign.  Its
% PHY evidence is nevertheless waveform truth: the existing PDSCH Tx/Rx,
% NTN-CDL channel and physical array projection are executed without proxy
% or fallback rows.

ip=inputParser;
ip.addRequired("configPath",@(x)ischar(x)||isstring(x));
ip.addParameter("RunTag","",@(x)ischar(x)||isstring(x));
ip.parse(configPath,varargin{:});

scenario=sixgr.ntn.resilientsync.buildScenario(string(configPath));
phyConfigPath=string(scenario.physical_layer.topology_proof_pdsch_config);
[phyCfg,phyProvenance]=sixgr.lls.loadConfig(phyConfigPath);
topology=sixgr.ntn.resilientsync.topology.buildTopology(scenario);
budget=sixgr.ntn.resilientsync.topology.computeLinkBudget(scenario,phyCfg,topology);

accessRows=find(topology.StateTable.Access);
if isempty(accessRows)
    error("sixgr:ntn:resilientsync:NoServiceAccess", ...
        "The configured satellite pass never satisfies minimum elevation.");
end
[~,localIndex]=max(topology.StateTable.ElevationDeg(accessRows));
selectedIndex=accessRows(localIndex);
operatingEsN0=double(phyCfg.simulation.snrDb(1));
availableEsN0=budget.DownlinkOccupiedRE_EsN0_dB(selectedIndex);
if logical(scenario.ntn_topology.link_budget.require_downlink_closure_at_phy_esn0) && ...
        availableEsN0 < operatingEsN0
    error("sixgr:ntn:resilientsync:DownlinkBudgetDoesNotClose", ...
        "Available occupied-RE Es/N0 %.3f dB is below the physical LLS point %.3f dB.", ...
        availableEsN0,operatingEsN0);
end

runTag=string(ip.Results.RunTag);
if strlength(strtrim(runTag))==0
    runTag="short_proof_"+string(datetime("now","TimeZone","UTC", ...
        "Format","yyyyMMdd_HHmmss"));
end
runTag=regexprep(runTag,"[^A-Za-z0-9_.-]","_");
repoRoot=localRepoRoot();
runDirectory=fullfile(repoRoot,char(scenario.outputs.output_root),char(runTag));
if exist(runDirectory,"dir")==7
    error("sixgr:ntn:resilientsync:OutputAlreadyExists", ...
        "Short proof output already exists: %s",runDirectory);
end
mkdir(runDirectory);
scenario.RunId=runTag;

writetable(topology.EndpointTable,fullfile(runDirectory,"ntn_endpoints.csv"));
writetable(topology.StateTable,fullfile(runDirectory,"ntn_orbit_access_latency_doppler.csv"));
writetable(topology.AccessIntervals,fullfile(runDirectory,"ntn_access_intervals.csv"));
writetable(budget,fullfile(runDirectory,"ntn_bidirectional_link_budget.csv"));
plotPaths=localPlots(runDirectory,topology,budget,scenario);

binding=table( ...
    string(scenario.ntn_topology.satellite.id), ...
    string(scenario.ntn_topology.service_ue.id), ...
    string(phyCfg.channel.model),double(phyCfg.channel.txAntennas), ...
    double(phyCfg.channel.rxAntennas),logical(phyCfg.antenna.enabled), ...
    operatingEsN0,availableEsN0, ...
    topology.StateTable.ElevationDeg(selectedIndex), ...
    topology.StateTable.SlantRange_m(selectedIndex), ...
    topology.StateTable.OneWayLatency_s(selectedIndex), ...
    topology.StateTable.DopplerShiftHz(selectedIndex), ...
    phyProvenance.ConfigSHA256,"CALIBRATED_LLS", ...
    'VariableNames',{'SatelliteId','ServiceUEId','ChannelProfile', ...
    'TxPhysicalElements','RxPhysicalElements','AntennaEnabled', ...
    'ConfiguredOperatingEsN0dB','AvailableLinkBudgetEsN0dB', ...
    'ElevationDeg','SlantRangeM','OneWayLatencyS','DopplerShiftHz', ...
    'PHYConfigSHA256','EvidenceClass'});
writetable(binding,fullfile(runDirectory,"topology_phy_binding.csv"));

phyResult=sixgr.lls.runLLS(phyConfigPath, ...
    "OutputRoot",fullfile(runDirectory,"phy"),"RunTag","waveform", ...
    "GeneratePlots",true);
if phyResult.Status~="complete_valid" || isempty(phyResult.TrialTable)
    error("sixgr:ntn:resilientsync:PhysicalProofFailed", ...
        "The bound PDSCH waveform run did not produce complete valid evidence.");
end
trials=phyResult.TrialTable;
requiredColumns=["AntennaPhysicalElementChannelApplied","ChannelModel", ...
    "NTNEnabled","CRCError"];
if ~all(ismember(requiredColumns,string(trials.Properties.VariableNames))) || ...
        ~all(trials.AntennaPhysicalElementChannelApplied) || ...
        ~all(trials.NTNEnabled) || ~all(string(trials.ChannelModel)=="NTN-CDL-D")
    error("sixgr:ntn:resilientsync:PhysicalBindingEvidenceMissing", ...
        "PDSCH trials do not prove the configured NTN-CDL-D physical array path.");
end

evidence=table( ...
    ["ntn_endpoints";"orbit_access_latency_doppler";"bidirectional_link_budget"; ...
     "topology_phy_binding";"pdsch_waveform_truth"], ...
    ["ANALYTICAL";"ANALYTICAL";"ANALYTICAL";"CALIBRATED_LLS";"CALIBRATED_LLS"], ...
    [false;false;false;true;true], ...
    ["ntn_endpoints.csv";"ntn_orbit_access_latency_doppler.csv"; ...
     "ntn_bidirectional_link_budget.csv";"topology_phy_binding.csv"; ...
     replace(string(phyResult.RunFolder),string(runDirectory)+filesep,"")], ...
    'VariableNames',{'Artifact','EvidenceClass','Measured','Path'});
writetable(evidence,fullfile(runDirectory,"evidence_index.csv"));
scenario.ConfigSHA256=string(scenario.ConfigSHA256);
sixgr.ntn.resilientsync.report.buildManifest(runDirectory,scenario, ...
    "SHORT_PHYSICAL_PROOF_PASS",evidence);

result=struct("Status","complete_valid","RunDirectory",string(runDirectory), ...
    "Topology",topology,"LinkBudgetTable",budget,"BindingTable",binding, ...
    "PHYResult",phyResult,"PlotPaths",plotPaths,"EvidenceTable",evidence);
end

function paths=localPlots(folder,topology,budget,scenario)
state=topology.StateTable;
paths=strings(4,1);
paths(1)=localLinePlot(folder,"ntn_access_elevation.png",state.Time_s, ...
    state.ElevationDeg,"Time (s)","Elevation (deg)", ...
    "Satellite access elevation",double(scenario.ntn_topology.access.minimum_elevation_deg));
paths(2)=localTwoAxisPlot(folder,"ntn_range_latency.png",state.Time_s, ...
    state.SlantRange_m/1e3,state.OneWayLatency_s*1e3, ...
    "Slant range (km)","One-way latency (ms)","Range and propagation latency");
paths(3)=localTwoAxisPlot(folder,"ntn_doppler.png",state.Time_s, ...
    state.DopplerShiftHz/1e3,state.DopplerRateHz_s, ...
    "Doppler shift (kHz)","Doppler rate (Hz/s)","Satellite Doppler and rate");
paths(4)=localTwoAxisPlot(folder,"ntn_link_budget.png",budget.ElevationDeg, ...
    budget.DownlinkOccupiedRE_EsN0_dB,budget.UplinkOccupiedRE_EsN0_dB, ...
    "DL occupied-RE Es/N0 (dB)","UL occupied-RE Es/N0 (dB)", ...
    "Bidirectional NTN link budget versus elevation");
end

function path=localLinePlot(folder,name,x,y,xlabelText,ylabelText,titleText,threshold)
fig=figure("Visible","off","Color","white","Position",[100 100 1000 620]);
cleanup=onCleanup(@()close(fig)); %#ok<NASGU>
plot(x,y,"LineWidth",2,"Color",[0.00 0.45 0.74]); hold on;
yline(threshold,"--","Minimum elevation","LineWidth",1.4);
grid on;xlabel(xlabelText);ylabel(ylabelText);title(titleText);
path=string(fullfile(folder,name));exportgraphics(fig,path,"Resolution",180);
end

function path=localTwoAxisPlot(folder,name,x,y1,y2,label1,label2,titleText)
fig=figure("Visible","off","Color","white","Position",[100 100 1000 620]);
cleanup=onCleanup(@()close(fig)); %#ok<NASGU>
yyaxis left;plot(x,y1,"LineWidth",2);ylabel(label1);
yyaxis right;plot(x,y2,"LineWidth",2);ylabel(label2);
grid on;xlabel("Time / elevation sample");title(titleText);
path=string(fullfile(folder,name));exportgraphics(fig,path,"Resolution",180);
end

function root=localRepoRoot()
here=fileparts(mfilename("fullpath"));
root=fileparts(fileparts(fileparts(fileparts(here))));
end
