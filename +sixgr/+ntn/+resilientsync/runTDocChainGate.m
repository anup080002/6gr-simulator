function result = runTDocChainGate(configPath,varargin)
%RUNTDOCCHAINGATE Exercise every calibrated waveform node used by the TDoc.
%
% This gate proves wiring only.  It does not replace the TDoc Monte-Carlo
% budgets or stopping rules.  Each PHY row is produced by a real Tx/channel/
% Rx execution and is explicitly marked QualificationEligible=false.

ip=inputParser;
ip.addRequired("configPath",@(x)ischar(x)||isstring(x));
ip.addParameter("OutputDirectory","",@(x)ischar(x)||isstring(x));
ip.parse(configPath,varargin{:});
scenario=sixgr.ntn.resilientsync.buildScenario(string(configPath));
rows=cell(0,1);

% Exact satellite/gateway/UE geometry and antenna binding.
topology=sixgr.ntn.resilientsync.topology.buildTopology(scenario);
[pdschCfg,pdschProv]=sixgr.lls.loadConfig( ...
    string(scenario.physical_layer.topology_proof_pdsch_config));
budget=sixgr.ntn.resilientsync.topology.computeLinkBudget(scenario,pdschCfg,topology);
topologyOk=any(topology.StateTable.Access) && any(topology.StateTable.GatewayAccess) && ...
    all(isfinite(budget.DownlinkOccupiedRE_EsN0_dB));
rows{end+1}=localRow("NTN_TOPOLOGY","bidirectional", ...
    "resilientsync.topology.buildTopology","same_state_range_latency_doppler", ...
    "circular_two_body_rotating_spherical_earth",topologyOk, ...
    sprintf("states=%d access_intervals=%d",height(topology.StateTable), ...
    height(topology.AccessIntervals)),false); %#ok<AGROW>

% PDSCH with the satellite 64-element and UE 4-element physical arrays.
pdschCfg.simulation.snrDb=10;
pdschCfg.simulation.minTransportBlocks=1;
pdschCfg.simulation.minBlockErrors=1;
pdschCfg.simulation.maxTransportBlocks=1;
pdschCfg.simulation.statisticalClass='diagnostic_only';
pdschCfg=sixgr.lls.validateConfig(pdschCfg,"ConfigPath",scenario.ConfigPath);
pdschHash=sixgr.util.sha256Hex(unicode2native(jsonencode(pdschCfg),'UTF-8'));
[pdschSummary,pdschTrials]=sixgr.lls.runSNRPoint(pdschCfg,pdschHash,1);
pdschOk=height(pdschTrials)==1 && ~pdschTrials.CRCError(1) && ...
    pdschTrials.AntennaPhysicalElementChannelApplied(1) && ...
    pdschTrials.AntennaTxPhysicalElements(1)==64 && ...
    pdschTrials.AntennaRxPhysicalElements(1)==4 && ...
    string(pdschTrials.ChannelModel(1))=="NTN-CDL-D";
rows{end+1}=localRow("PDSCH","DL", ...
    "sixgr.phy.dl.PDSCH_Tx","sixgr.phy.dl.PDSCH_Rx", ...
    string(pdschTrials.ChannelModel(1)),pdschOk, ...
    sprintf("TB=%d CRCError=%d Tx=%d Rx=%d",pdschSummary.NumTB, ...
    pdschTrials.CRCError(1),pdschTrials.AntennaTxPhysicalElements(1), ...
    pdschTrials.AntennaRxPhysicalElements(1)),false); %#ok<AGROW>

% Physical TRS downlink measurement node.
gateRoot=string(ip.Results.OutputDirectory);
if strlength(strtrim(gateRoot))==0
    gateRoot=string(tempname);
end
if exist(gateRoot,"dir")~=7,mkdir(gateRoot);end
trsFolder=fullfile(gateRoot,"trs");mkdir(trsFolder);
trsSource=sixgr.lls6g.config.loadScenarioConfig( ...
    localRepoPath(string(scenario.physical_layer.trs_scenario_config)));
trsInternal=sixgr.lls6g.buildInternalConfig(trsSource,trsFolder);
trs=sixgr.phy.trs.runStrictTRSValidation(trsInternal, ...
    "RunFolder",trsFolder,"RunId","ntn_tdoc_chain_gate_trs", ...
    "ScenarioName","ntn_tdoc_chain_gate","WriteArtifacts",false);
rows{end+1}=localRow("TRS","DL_measurement", ...
    "sixgr.phy.trs.generateTRSWaveform","sixgr.phy.trs.runStrictTRSValidation", ...
    "configured_TRS_channel",logical(trs.StrictOk), ...
    sprintf("StrictOk=%d",logical(trs.StrictOk)),false); %#ok<AGROW>

% PRACH Tx and receiver-only correlation detection.
prachSource=sixgr.lls6g.config.loadScenarioConfig( ...
    localRepoPath(string(scenario.physical_layer.prach_scenario_config)));
prachBase=prachSource.toStruct();
prachCfg=sixgr.phy.prach.buildPRACHConfigFromScenario(prachBase, ...
    "RunFolder",fullfile(gateRoot,"prach"),"ScenarioName","ntn_tdoc_chain_gate");
occasion=sixgr.rach.mapPRACHToOccasion(prachCfg,"OccasionIndex",1);
preamble=double(prachCfg.PreambleIndex(1));
prachTx=sixgr.phy.prach.generatePRACHWaveform(prachCfg, ...
    "Occasion",occasion,"PreambleIndex",preamble);
prachDet=sixgr.phy.prach.detectPRACHWaveform(prachTx.Waveform,prachCfg, ...
    "Occasion",occasion,"CandidatePreambles",0:min(63,double(prachCfg.NumPreambles)-1), ...
    "DetectionThreshold",0,"DetectorBackend","toolbox_peak");
prachOk=double(prachDet.DetectedPreambleIndex)==preamble && ...
    ~logical(prachDet.ProxyUsed) && strlength(string(prachDet.UsedOracleFields))==0;
rows{end+1}=localRow("PRACH","UL_access", ...
    "sixgr.phy.prach.generatePRACHWaveform","sixgr.phy.prach.detectPRACHWaveform", ...
    "receiver_waveform_correlation",prachOk, ...
    sprintf("expected=%d detected=%d",preamble,double(prachDet.DetectedPreambleIndex)),false); %#ok<AGROW>

% PUSCH production transmitter/channel/receiver.
[puschCfg,~]=sixgr.lls.loadConfig(string(scenario.physical_layer.pusch_config));
puschCfg.simulation.snrDb=20;
puschCfg.simulation.minTransportBlocks=1;
puschCfg.simulation.minBlockErrors=1;
puschCfg.simulation.maxTransportBlocks=1;
puschCfg.simulation.statisticalClass='diagnostic_only';
puschCfg.synchronizationResidual.enabled=false;
puschCfg.synchronizationResidual.timingErrorSeconds=0;
puschCfg.synchronizationResidual.frequencyErrorHz=0;
puschCfg.synchronizationResidual.source='tdoc_chain_gate_zero_residual';
puschCfg=sixgr.lls.validateConfig(puschCfg,"ConfigPath",scenario.ConfigPath);
puschHash=sixgr.util.sha256Hex(unicode2native(jsonencode(puschCfg),'UTF-8'));
[puschSummary,puschTrials]=sixgr.lls.runSNRPoint(puschCfg,puschHash,1);
puschOk=height(puschTrials)==1 && ~puschTrials.CRCError(1) && ...
    string(puschTrials.LLRSource(1))=="nrPUSCHDecode_soft_llr" && ...
    string(puschTrials.CRCSource(1))=="decoded_transport_block_crc" && ...
    strlength(string(puschTrials.ChannelRealizationSource(1)))>0;
rows{end+1}=localRow("PUSCH","UL_data", ...
    "sixgr.phy.ul.PUSCH_Tx","sixgr.phy.ul.PUSCH_Rx", ...
    string(puschTrials.ChannelModel(1)),puschOk, ...
    sprintf("TB=%d CRCError=%d",puschSummary.NumTB,puschTrials.CRCError(1)),false); %#ok<AGROW>

% PUCCH typed UCI through the real NTN-TDL-D path.
bits=int8(mod((0:double(scenario.physical_layer.pucch_payload_bits)-1).',2));
fixture=sixgr.phy.pucch.PUCCHFixtureFactory.connected( ...
    double(scenario.physical_layer.pucch_format),bits, ...
    "SCS",double(scenario.physical_layer.residual_scs_khz));
pucch=sixgr.link.runPUCCHWaveformTrial(fixture.Carrier, ...
    "Assignment",fixture.Assignment,"Report",fixture.Report, ...
    "ReceiverContext",fixture.Context,"Carrier",fixture.Carrier, ...
    "ChannelProfile","NTN-TDL-D","SNR_dB",20, ...
    "Seed",double(scenario.seed)+991,"CFOHz",0,"TimingOffsetSamples",0, ...
    "DelaySpreadSeconds",30e-9,"DopplerHz",0);
pucchOk=logical(pucch.Ok) && string(pucch.ChannelProfile)=="NTN-TDL-D";
rows{end+1}=localRow("PUCCH","UL_control", ...
    "sixgr.phy.pucch.PUCCH_Tx","sixgr.phy.pucch.PUCCH_Rx", ...
    string(pucch.ChannelProfile),pucchOk, ...
    sprintf("Ok=%d BitErrors=%d",logical(pucch.Ok),double(pucch.BitErrors)),false); %#ok<AGROW>

gateTable=struct2table(vertcat(rows{:}));
writetable(gateTable,fullfile(gateRoot,"ntn_tdoc_tx_rx_chain_gate.csv"));
if ~all(gateTable.Pass)
    failed=strjoin(gateTable.Node(~gateTable.Pass),", ");
    error("sixgr:ntn:resilientsync:TDocChainGateFailed", ...
        "Required TDoc physical node(s) failed: %s",char(failed));
end
result=struct("Status","CHAIN_GATE_PASS","GateTable",gateTable, ...
    "OutputDirectory",gateRoot,"ScenarioConfigSHA256",scenario.ConfigSHA256, ...
    "PDSCHConfigSHA256",pdschProv.ConfigSHA256);
end

function row=localRow(node,direction,tx,rx,channel,pass,detail,eligible)
row=struct("Node",string(node),"Direction",string(direction), ...
    "TxAuthority",string(tx),"RxAuthority",string(rx), ...
    "ChannelOrModel",string(channel),"ExecutionBackend","waveform_truth", ...
    "ApproximationMode","none","Pass",logical(pass),"Detail",string(detail), ...
    "QualificationEligible",logical(eligible),"EvidenceClass","CALIBRATED_LLS");
if node=="NTN_TOPOLOGY"
    row.ExecutionBackend="analytical_geometry";
    row.EvidenceClass="ANALYTICAL";
end
end

function path=localRepoPath(raw)
if java.io.File(char(raw)).isAbsolute()
    path=raw;return;
end
here=fileparts(mfilename("fullpath"));
root=fileparts(fileparts(fileparts(here)));
path=string(fullfile(root,char(raw)));
end
