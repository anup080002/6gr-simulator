function out = sourceErrorToULRP(state, errors, rule)
%SOURCEERRORTOULRP Map state errors to signed ULRP timing/frequency error.

requiredState = ["SatellitePosition_m","SatelliteVelocity_m_s", ...
    "UEPosition_m","UEVelocity_m_s"];
for name = requiredState
    if ~isfield(state, name)
        error("sixgr:ntn:resilientsync:MissingGeometryState", ...
            "Source-error mapping requires state.%s.", char(name));
    end
end
qGeom = sixgr.ntn.resilientsync.geometry.slantRangeAndRate( ...
    state.SatellitePosition_m, state.SatelliteVelocity_m_s, ...
    state.UEPosition_m, state.UEVelocity_m_s);
q = qGeom.LOSUnitVector(:);
r = qGeom.Range_m;
vRel = (state.SatelliteVelocity_m_s - state.UEVelocity_m_s).';
deltaPosition = (errors.DeltaSatellitePosition_m - errors.DeltaUEPosition_m).';
deltaVelocity = (errors.DeltaSatelliteVelocity_m_s - errors.DeltaUEVelocity_m_s).';
deltaR = q.' * deltaPosition;
projection = eye(3) - q*q.';
deltaRdot = q.' * deltaVelocity + ((projection*vRel).' / r) * deltaPosition;
c = double(rule.SpeedOfLight_m_s);
deltaTau = deltaR / c;
eT = -double(rule.KappaT) * deltaTau + ...
    double(rule.TimingCommon_s) + double(rule.TimingCorrection_s);
eF = -(double(rule.ULCarrier_Hz)/c) * deltaRdot + ...
    double(rule.DLToULFrequency_Hz) + ...
    double(rule.ULCarrier_Hz) * double(rule.OscillatorFractional) + ...
    double(rule.FrequencyCommon_Hz) + double(rule.FrequencyCorrection_Hz);
out = struct("DeltaRange_m", deltaR, "DeltaRangeRate_m_s", deltaRdot, ...
    "DeltaTauSL_s", deltaTau, "ULRPArrivalError_s", eT, ...
    "ULFrequencyError_Hz", eF, "KappaT", double(rule.KappaT), ...
    "SignConvention", "eT=-kappaT*deltaTauSL+common+corr");
end
