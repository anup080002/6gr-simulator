function state = solveSatelliteStateForElevation(earthRadiusM, altitudeM, elevationRad, mu)
%SOLVESATELLITESTATEFORELEVATION Exact spherical-Earth circular-LEO state.

arguments
    earthRadiusM (1,1) double {mustBePositive,mustBeFinite}
    altitudeM (1,1) double {mustBePositive,mustBeFinite}
    elevationRad (1,1) double {mustBeFinite}
    mu (1,1) double {mustBePositive,mustBeFinite} = 3.986004418e14
end
if elevationRad < 0 || elevationRad > pi/2
    error("sixgr:ntn:resilientsync:ElevationOutOfRange", ...
        "Elevation must be in [0, pi/2] radians.");
end
orbitRadius = earthRadiusM + altitudeM;
rangeM = -earthRadiusM * sin(elevationRad) + ...
    sqrt(orbitRadius^2 - earthRadiusM^2 * cos(elevationRad)^2);
ue = [earthRadiusM, 0, 0];
los = [sin(elevationRad), cos(elevationRad), 0];
sat = ue + rangeM .* los;
satRadial = sat ./ norm(sat);
satTangent = [-satRadial(2), satRadial(1), 0];
satVelocity = sqrt(mu / orbitRadius) .* satTangent;
state = struct( ...
    "SatellitePositionECEF_m", sat, ...
    "SatelliteVelocityECEF_m_s", satVelocity, ...
    "UEPositionECEF_m", ue, ...
    "UEVelocityECEF_m_s", [0,0,0], ...
    "Range_m", rangeM, ...
    "Elevation_rad", elevationRad, ...
    "OrbitRadius_m", orbitRadius, ...
    "Model", "exact_spherical_earth_circular_orbit");
end
