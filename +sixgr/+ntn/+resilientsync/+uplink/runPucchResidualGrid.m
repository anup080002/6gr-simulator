function result = runPucchResidualGrid(scenario,runDirectory)
%RUNPUCCHRESIDUALGRID Execute typed UCI through NTN-TDL PUCCH waveform PHY.

format=double(scenario.physical_layer.pucch_format);
numBits=double(scenario.physical_layer.pucch_payload_bits);
bits=int8(mod((0:numBits-1).',2));
fixture=sixgr.phy.pucch.PUCCHFixtureFactory.connected(format,bits, ...
    "SCS",double(scenario.physical_layer.residual_scs_khz));
ofdm=nrOFDMInfo(fixture.Carrier);
timing=double(scenario.residual_grid.timing_error_us(:))*1e-6;
timingSamples=round(timing*double(ofdm.SampleRate));
frequency=double(scenario.residual_grid.frequency_error_khz(:))*1e3;
snr=double(scenario.physical_layer.residual_snr_db(:));
nTrials=double(scenario.physical_layer.bler_blocks_min);
folder=fullfile(char(runDirectory),'raw','campaign_d_pucch');
if exist(folder,'dir')~=7,mkdir(folder);end
summaryRows=cell(numel(timing)*numel(frequency)*numel(snr),1);indexRows=cell(size(summaryRows));index=0;
for ti=1:numel(timing)
    for fi=1:numel(frequency)
        for si=1:numel(snr)
            index=index+1;trialRows=cell(nTrials,1);
            for trialIndex=1:nTrials
                trial=sixgr.link.runPUCCHWaveformTrial(fixture.Carrier, ...
                    "Assignment",fixture.Assignment,"Report",fixture.Report, ...
                    "ReceiverContext",fixture.Context,"Carrier",fixture.Carrier, ...
                    "ChannelProfile","NTN-TDL-D","SNR_dB",snr(si), ...
                    "Seed",double(scenario.seed)+index*100000+trialIndex, ...
                    "CFOHz",frequency(fi),"TimingOffsetSamples",timingSamples(ti), ...
                    "DelaySpreadSeconds",30e-9,"DopplerHz",0);
                trialRows{trialIndex}=localTrialRow(trialIndex,timing(ti),timingSamples(ti), ...
                    frequency(fi),snr(si),trial);
            end
            trials=struct2table(vertcat(trialRows{:}));
            file=sprintf('pucch_t%+gus_f%+gkhz_snr%+gdb.csv', ...
                timing(ti)*1e6,frequency(fi)/1e3,snr(si));
            file=regexprep(file,'[^A-Za-z0-9_.-]','_');path=fullfile(folder,file);writetable(trials,path);
            errors=sum(~trials.Ok);
            [lo,hi]=sixgr.lls.stats.wilsonInterval(errors,nTrials, ...
                double(scenario.physical_layer.confidence_level));
            summaryRows{index}={timing(ti),timingSamples(ti),frequency(fi),snr(si),nTrials, ...
                errors,errors/nTrials,lo,hi,mean(trials.BitErrors), ...
                "NTN-TDL-D","CALIBRATED_LLS"};
            indexRows{index}={replace(string(path),string(runDirectory)+filesep,""),height(trials), ...
                errors,localFileHash(path),timing(ti),frequency(fi),snr(si), ...
                "CALIBRATED_LLS"};
        end
    end
end
summary=cell2table(vertcat(summaryRows{:}),'VariableNames', ...
    {'ResidualTimingError_s','ResidualTimingError_samples','ResidualFrequencyError_Hz', ...
    'SNR_dB','NumTrials','NumErrors','ErrorRate','WilsonLower','WilsonUpper', ...
    'MeanBitErrors','ChannelProfile','Provenance'});
summary.Properties.VariableUnits={'s','sample','Hz','dB','','','1','1','1','','',''};
fileIndex=cell2table(vertcat(indexRows{:}),'VariableNames', ...
    {'RelativePath','Rows','Errors','SHA256','ResidualTimingError_s', ...
    'ResidualFrequencyError_Hz','SNR_dB','Provenance'});
fileIndex.Properties.VariableUnits={'','','','','s','Hz','dB',''};
tables=struct('pucch_residual_summary',summary,'pucch_trial_file_index',fileIndex);
evidence=table(["pucch_residual_summary";"pucch_trial_file_index"], ...
    repmat("CALIBRATED_LLS",2,1),true(2,1),repmat("PRODUCED",2,1), ...
    'VariableNames',{'Artifact','EvidenceClass','Measured','Status'});
result=struct('Status','COMPLETE','Tables',tables,'Evidence',evidence);
end

function digest=localFileHash(path)
fid=fopen(path,'rb');
if fid<0,error('sixgr:ntn:resilientsync:ArtifactReadFailed','Cannot hash %s.',path);end
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
digest=sixgr.util.sha256Hex(fread(fid,Inf,'*uint8'));
end

function row=localTrialRow(index,timingS,timingSamples,frequencyHz,snrDb,trial)
row=struct('Trial',index,'ResidualTimingError_s',timingS, ...
    'ResidualTimingError_samples',timingSamples,'ResidualFrequencyError_Hz',frequencyHz, ...
    'SNR_dB',snrDb,'Ok',logical(trial.Ok),'BitErrors',double(trial.BitErrors), ...
    'ReceiverDTX',logical(trial.ReceiverDTX),'CRCFailed',logical(trial.CRCFailed), ...
    'ContentMismatch',logical(trial.ContentMismatch),'InputMeasuredSINR_dB', ...
    double(trial.InputMeasuredSINR_dB),'NoiseVariance',double(trial.NoiseVariance), ...
    'ChannelProfile',string(trial.ChannelProfile),'InjectedCFO_Hz',frequencyHz, ...
    'InjectedTimingOffset_samples',timingSamples, ...
    'ExecutionBackend','waveform_truth','ApproximationMode','none', ...
    'Provenance','CALIBRATED_LLS');
end
