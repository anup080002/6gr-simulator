        function index=indexForBytes(bytes,tableID)
            arguments
                bytes (1,1) double {mustBeInteger,mustBeNonnegative}
                tableID
            end
            bounds=sixgr.l2.mac.BSRTableR18.upperBounds(tableID);
            if lower(string(tableID))=="refined8bit" || ...
                    lower(string(tableID))=="refinedlong" || ...
                    lower(string(tableID))=="table3"
                if bytes<=4751
                    error("sixgr:mac:RefinedBSROutOfRange", ...
                        "Refined table begins above 4751 bytes.");
                end
            end
            index=find(bytes<=bounds,1)-1;
            if isempty(index) || isnan(bounds(index+1))
                error("sixgr:mac:ReservedBSRIndex", ...
                    "No reportable BSR index for %g bytes.",bytes);
            end
        end

        function value=table(tableID)
            bounds=sixgr.l2.mac.BSRTableR18.upperBounds(tableID);
            n=numel(bounds);
            lowerBounds=[NaN bounds(1:end-1)];
            value=table((0:n-1).',lowerBounds(:),bounds(:), ...
                'VariableNames',{'Index','LowerExclusive','UpperInclusive'});
            value.Reserved=isnan(value.UpperInclusive);
        end
