classdef MACInvariantGuard
    %MACINVARIANTGUARD Typed fail-closed negative-case boundary.
    methods (Static)
        function reject(faultType)
            faultType=lower(string(faultType));
            mapping=containers.Map( ...
                {'bsr_approx_table','byte_conservation_error', ...
                'configured_grant_without_activation','drx_sleep', ...
                'dtx_as_ack','duplicate_ack','duplicate_ce', ...
                'grant_not_decoded','illegal_tdd_symbol','inactive_bwp', ...
                'late_feedback','lcid_reserved','mac_pdu_overrun', ...
                'measurement_gap','missing_k1','phr_approx_mapping', ...
                'soft_buffer_wrong_position','sps_wrong_occasion', ...
                'sr_wrong_resource','ta_expired_ul_tx','wrong_cell', ...
                'wrong_codeword','wrong_ndi_epoch','wrong_rv_sequence', ...
                'wrong_tb_id'}, ...
                {'sixgr:mac:BSRTableMismatch', ...
                'sixgr:mac:LineageConservationFailure', ...
                'sixgr:mac:ConfiguredGrantInactive','sixgr:mac:UEIneligible', ...
                'sixgr:mac:InvalidHARQFeedbackContext', ...
                'sixgr:mac:DuplicateHARQFeedback','sixgr:mac:DuplicateMACCE', ...
                'sixgr:mac:GrantAuthorityMissing', ...
                'sixgr:mac:TDDResourceUnavailable','sixgr:mac:UEIneligible', ...
                'sixgr:mac:LateHARQFeedback','sixgr:mac:ReservedLCID', ...
                'sixgr:mac:MACPDUOverrun','sixgr:mac:UEIneligible', ...
                'sixgr:mac:TimingContextMissing', ...
                'sixgr:mac:PHRMappingMismatch', ...
                'sixgr:mac:SoftBufferProvenanceMismatch', ...
                'sixgr:mac:SPSWrongOccasion','sixgr:mac:SRResourceMismatch', ...
                'sixgr:mac:TimeAlignmentInvalid', ...
                'sixgr:mac:HARQIdentityMismatch', ...
                'sixgr:mac:HARQIdentityMismatch', ...
                'sixgr:mac:HARQIdentityMismatch', ...
                'sixgr:mac:RVSequenceMismatch', ...
                'sixgr:mac:HARQIdentityMismatch'});
            key=char(faultType);
            if ~isKey(mapping,key)
                error("sixgr:mac:UnknownFaultInjection", ...
                    "Unknown MAC fault %s.",faultType);
            end
            id=mapping(key);
            error(id,"Rejected injected MAC fault %s.",faultType);
        end
    end
end
