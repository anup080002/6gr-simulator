function grant = bindReceivedCSIProvenance(grant, ue, cfg)
%BINDRECEIVEDCSIPROVENANCE Bind a NEW grant to its admitted receiver record.
% Never refresh an already frozen or HARQ spatial decision from latest CSI.
if upper(string(sixgr.util.structGet(grant,'Direction',"")))~="DL" || ...
        sixgr.phy.grant.isExplicitHARQRetransmission(grant) || ...
        logical(sixgr.util.structGet(grant,'PHYGrant.IsFrozen',false))
    return;
end
p=sixgr.util.structGet(ue,'CSIReportProvenance',struct());
if ~isstruct(p) || isempty(fieldnames(p)), return; end
assert(string(p.Version)=="received_csi_provenance/v1", ...
    'sixgr:mac:InvalidCSIProvenance','Use the receiver-only provenance capsule.');
assert(isscalar(p.Direction) && upper(string(p.Direction))=="DL", ...
    'sixgr:mac:CSIProvenanceIdentityMismatch', ...
    'A DL grant may retain only a DL received CSI report.');
for field=["RNTI","UEIndex","ServingCell"]
    expected=sixgr.util.structGet(ue,field,NaN);
    if isfinite(expected)
        assert(isequal(p.(field),expected),'sixgr:mac:CSIProvenanceIdentityMismatch', ...
            'Received CSI belongs to another scheduler UE/cell.');
    end
end
epoch=sixgr.util.structGet(cfg,'phy.csi.reportConfigurationEpoch',NaN);
if isfinite(epoch) && isfinite(p.CSIConfigurationEpoch)
    assert(epoch==p.CSIConfigurationEpoch,'sixgr:mac:CSIProvenanceConfigurationMismatch', ...
        'Do not apply a retired CSI configuration epoch to a new grant.');
end
configID=string(sixgr.util.structGet(cfg,'phy.csi.reportConfiguration.ReportConfigID',""));
if strlength(configID)>0 && strlength(p.CSIReportConfigID)>0
    assert(configID==p.CSIReportConfigID,'sixgr:mac:CSIProvenanceConfigurationMismatch', ...
        'Do not apply another installed report configuration to a new grant.');
end
% received_csi_provenance/v1 retains one-based runtime report slots. The
% scheduler's legacy Slot is caller-defined (zero-based in coupled truth,
% one-based in some MAC callers), so it cannot establish causal ordering.
% ControlAbsoluteSlot is the explicit zero-based control-decision occasion;
% neither a later data slot nor a caller's Slot can authorize future CSI.
controlSlot0=localControlDecisionSlot(grant);
reportSlots=["SourceSlot","DueSlot","DeliveredSlot"];
assert(all(isfield(p,cellstr(reportSlots))) && ...
    all(arrayfun(@(f)localIntegerAtLeast(p.(f),1),reportSlots)), ...
    'sixgr:mac:InvalidCSIProvenanceReportClock', ...
    'Received CSI source, due and delivery slots must be one-based integers.');
assert(p.SourceSlot<=p.DueSlot && p.DueSlot<=p.DeliveredSlot && ...
    p.DeliveredSlot-1<=controlSlot0, ...
    'sixgr:mac:FutureCSIProvenance', ...
    'Received CSI must precede the explicit zero-based control decision.');
% Recheck the unchanged report operands against the actual scheduler clock.
% An old record lacking operands cannot be upgraded by adding a later clock.
decisionClock=sixgr.util.structGet(ue,'CSIReportDecisionContext',struct());
assert(isstruct(decisionClock) && isscalar(decisionClock), ...
    'sixgr:mac:InvalidCSIProvenanceDecisionClock', ...
    'The consumer sample clock must be an explicit scalar owner-clock record.');
if p.ReceiverObservationBound
    assert(~isempty(fieldnames(decisionClock)), ...
        'sixgr:mac:MissingCSIProvenanceDecisionClock', ...
        'A receiver-bound CSI report requires the actual consumer sample clock.');
end
if ~isempty(fieldnames(decisionClock))
    assert(all(isfield(decisionClock, ...
        {'ClockDomain','ClockEpoch','SampleRateHz','AtSample'})) && ...
        (ischar(decisionClock.ClockDomain) || isstring(decisionClock.ClockDomain)) && ...
        isscalar(string(decisionClock.ClockDomain)) && ...
        strlength(string(decisionClock.ClockDomain))>0 && ...
        localIntegerAtLeast(decisionClock.ClockEpoch,0) && ...
        isnumeric(decisionClock.SampleRateHz) && isreal(decisionClock.SampleRateHz) && ...
        isscalar(decisionClock.SampleRateHz) && isfinite(decisionClock.SampleRateHz) && ...
        decisionClock.SampleRateHz>0 && localIntegerAtLeast(decisionClock.AtSample,0), ...
        'sixgr:mac:InvalidCSIProvenanceDecisionClock', ...
        'Retain a complete owner domain, epoch, sample rate and integer sample cutoff.');
end
raw=p; raw.SourceSignal="received_CSI_UCI"; raw.CSIUCIDecodeOk=true;
checked=sixgr.truth.captureReceivedCSIProvenance(raw,decisionClock);
assert(~p.ReceiverObservationBound || checked.ReceiverObservationBound, ...
    'sixgr:mac:InvalidCSIProvenanceDecisionClock', ...
    'A bound receiver capsule cannot lose its completed observation operands.');
grant.CSIReportProvenance=p;
grant.CSIReportProvenance.ReceiverObservationBound= ...
    p.ReceiverObservationBound && checked.ReceiverObservationBound;
if p.ReceiverObservationBound
    grant.CSIReportProvenance.BindingStatus=checked.BindingStatus;
end
grant.CSIReportDecisionContext=decisionClock;
end

function slot0=localControlDecisionSlot(grant)
assert(isfield(grant,'ControlAbsoluteSlot'), ...
    'sixgr:mac:MissingCSIProvenanceControlClock', ...
    'Received CSI requires explicit zero-based ControlAbsoluteSlot; never infer it from Slot or data timing.');
slot0=grant.ControlAbsoluteSlot;
assert(localIntegerAtLeast(slot0,0), ...
    'sixgr:mac:InvalidCSIProvenanceControlClock', ...
    'ControlAbsoluteSlot must be a finite zero-based nonnegative integer.');
% Timing may not yet be resolved at the MAC attachment boundary. If it is
% supplied, it must corroborate the same control occasion, never replace it.
if isfield(grant,'TimingDecision')
    timing=grant.TimingDecision;
    assert(isstruct(timing) && isscalar(timing), ...
        'sixgr:mac:InvalidCSIProvenanceControlClock','Malformed canonical timing evidence.');
    if ~isempty(fieldnames(timing))
        assert(isequal(sixgr.util.structGet(timing,'Valid',false),true) && ...
            isfield(timing,'ControlAbsoluteSlot') && ...
            localIntegerAtLeast(timing.ControlAbsoluteSlot,0) && ...
            timing.ControlAbsoluteSlot==slot0, ...
            'sixgr:mac:InvalidCSIProvenanceControlClock', ...
            'Canonical timing must be valid and agree with the explicit control decision.');
    end
end
end

function tf=localIntegerAtLeast(value,minimum)
tf=isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && value==fix(value) && value>=minimum;
end
