function row=harqPRBDeferral(grant,available,budgetSymbols)
% Actual pending-process decision, not an allocated or transmitted grant.
row=table(double(grant.Slot),double(grant.RNTI), ...
    double(grant.HARQ.HarqID),string(grant.Direction), ...
    double(grant.SymbolAllocation(:).'),double(budgetSymbols(:).'), ...
    "no_contiguous_prb_run_for_stored_harq_allocation", ...
    'VariableNames',{'Slot','RNTI','HARQProcess','Direction', ...
    'StoredSymbolAllocation','AvailableSymbolAllocation','Reason'});
% PRB evidence is retained by the scheduler's ResourceExclusions table.
validateattributes(available,{'numeric'},{'real','finite','integer','nonnegative'});
end
