function application = csiReportGrantApplication(grant, phyGrant)
%CSIREPORTGRANTAPPLICATION Record actual frozen operands, not TX/RX success.
application=struct();
p=sixgr.util.structGet(grant,'CSIReportProvenance',struct());
if ~isstruct(p) || isempty(fieldnames(p)), return; end
prec=phyGrant.PrecodingState;
application=struct('Source',"frozen_grant_operands_not_waveform_application", ...
    'ReportIdentity',p.ReportIdentity,'ObservationID',p.ObservationID, ...
    'ReceiverObservationBound',p.ReceiverObservationBound, ...
    'GrantContextId',string(phyGrant.GrantContextId), ...
    'ReportedCQI',p.CQI,'ReportedRI',p.RI,'ReportedPMI',p.PMI,'ReportedCRI',p.CRI, ...
    'ScheduledCQI',double(sixgr.util.structGet(grant,'CQIUsed',NaN)), ...
    'ScheduledMCS',double(sixgr.util.structGet(grant,'MCSIndex',NaN)), ...
    'FrozenNumLayers',double(phyGrant.AntennaArchitecture.NumLayers), ...
    'FrozenPMI',double(sixgr.util.structGet(prec,'PMI',NaN)), ...
    'FrozenCSIResourceIndex',double(sixgr.util.structGet(prec,'CSIResourceIndex',NaN)), ...
    'FrozenPrecoderSource',string(sixgr.util.structGet(prec,'Source',"")), ...
    'SelectedMatrixSHA256',string(prec.SelectedMatrixSHA256), ...
    'AppliedMatrixSHA256',string(prec.AppliedMatrixSHA256), ...
    'WaveformApplicationVerified',false);
end
