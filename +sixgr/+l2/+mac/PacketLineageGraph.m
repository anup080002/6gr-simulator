classdef PacketLineageGraph < handle
    %PACKETLINEAGEGRAPH Immutable packet/segment/PDU/TB/attempt/delivery graph.
    properties (SetAccess=private)
        Nodes table
        Edges table
        DeliveredPackets (1,:) string = strings(1,0)
    end
    methods
        function obj=PacketLineageGraph()
            obj.Nodes=table('Size',[0 10], ...
                'VariableTypes',{'string','string','string','string', ...
                'double','double','double','string','string','string'}, ...
                'VariableNames',{'NodeID','NodeType','ParentNodeID', ...
                'PacketID','FlowID','UEID','Bytes','SHA256', ...
                'CreatedEventID','Disposition'});
            obj.Edges=table('Size',[0 7], ...
                'VariableTypes',{'string','string','string','string', ...
                'double','double','string'}, ...
                'VariableNames',{'EdgeID','FromNodeID','ToNodeID', ...
                'EdgeType','Bytes','Bits','SourceEventID'});
        end
        function nodeID=addNode(obj,nodeType,parentNodeID,packetID,flowID,ueID,bytes,eventID,disposition)
            if strlength(string(parentNodeID))>0 && ...
                    ~any(obj.Nodes.NodeID==string(parentNodeID))
                error("sixgr:mac:PacketLineageOrphan", ...
                    "Parent node %s is absent.",string(parentNodeID));
            end
            data=struct("NodeType",string(nodeType),"ParentNodeID",string(parentNodeID), ...
                "PacketID",string(packetID),"FlowID",flowID,"UEID",ueID, ...
                "Bytes",bytes,"CreatedEventID",string(eventID), ...
                "Disposition",string(disposition));
            nodeID=sixgr.l2.mac.MACHash.of(data);
            if any(obj.Nodes.NodeID==nodeID)
                error("sixgr:mac:DuplicateLineageNode","Duplicate lineage node.");
            end
            obj.Nodes(end+1,:)={nodeID,string(nodeType),string(parentNodeID), ...
                string(packetID),double(flowID),double(ueID),double(bytes), ...
                sixgr.l2.mac.MACHash.of(data),string(eventID),string(disposition)};
            if strlength(string(parentNodeID))>0
                edgeID=sixgr.l2.mac.MACHash.of(parentNodeID+"|"+nodeID);
                obj.Edges(end+1,:)={edgeID,string(parentNodeID),nodeID, ...
                    "transformation",double(bytes),double(bytes)*8,string(eventID)};
            end
        end
        function counted=recordDelivery(obj,packetID)
            packetID=string(packetID);
            counted=~ismember(packetID,obj.DeliveredPackets);
            if counted, obj.DeliveredPackets(end+1)=packetID; end
        end
    end
end
