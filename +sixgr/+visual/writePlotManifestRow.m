function row = writePlotManifestRow(plotId, imagePath, sourceCsv, sourceTable, xVariable, yVariables, stats, varargin)
%WRITEPLOTMANIFESTROW Build one plot-manifest row.

opts = struct( ...
    "PlotType", "", ...
    "PlotRenderStatus", "", ...
    "PlotSuppressionReason", "", ...
    "IsUnavailableCard", false, ...
    "CountsAsRealPlot", true, ...
    "VisualValidity", "", ...
    "WarningBannerText", "", ...
    "AxisTransform", "", ...
    "YFloorApplied", false, ...
    "AggregationMethod", "", ...
    "RawRowCount", NaN, ...
    "AggregatedRowCount", NaN, ...
    "DuplicateRowCount", NaN, ...
    "SourceHash", "", ...
    "ActualMimeType", "", ...
    "DeclaredMimeType", "", ...
    "Extension", "", ...
    "SHA256", "", ...
    "ByteCount", 0);
if rem(numel(varargin), 2) ~= 0
    error("sixgr:visual:writePlotManifestRow:BadNV", "Name-value inputs must come in pairs.");
end
for i = 1:2:numel(varargin)
    name = string(varargin{i});
    if isfield(opts, name)
        opts.(name) = varargin{i + 1};
    else
        error("sixgr:visual:writePlotManifestRow:BadOpt", "Unknown option: %s", char(name));
    end
end

if isempty(stats)
    stats = struct("RowCount", NaN, "UniqueXCount", NaN, "NonNaNYCount", NaN);
end

row = struct( ...
    "PlotId", string(plotId), ...
    "ImagePath", string(imagePath), ...
    "SourceCSV", string(sourceCsv), ...
    "SourceTable", string(sourceTable), ...
    "XVariable", string(xVariable), ...
    "YVariables", string(yVariables), ...
    "RowCount", double(localStructField(stats, "RowCount", NaN)), ...
    "UniqueXCount", double(localStructField(stats, "UniqueXCount", NaN)), ...
    "NonNaNYCount", double(localStructField(stats, "NonNaNYCount", NaN)), ...
    "UniqueYCount", double(localStructField(stats, "UniqueYCount", NaN)), ...
    "PlotType", string(localDefault(opts.PlotType, localStructField(stats, "PlotType", ""))), ...
    "PlotRenderStatus", string(localDefault(opts.PlotRenderStatus, localStructField(stats, "PlotRenderStatus", ""))), ...
    "PlotSuppressionReason", string(localDefault(opts.PlotSuppressionReason, localStructField(stats, "PlotSuppressionReason", ""))), ...
    "IsUnavailableCard", logical(localDefault(opts.IsUnavailableCard, localStructField(stats, "IsUnavailableCard", false))), ...
    "CountsAsRealPlot", logical(localDefault(opts.CountsAsRealPlot, localStructField(stats, "CountsAsRealPlot", true))), ...
    "VisualValidity", string(localResolveVisualValidity(opts, stats)), ...
    "WarningBannerText", string(localDefault(opts.WarningBannerText, localStructField(stats, "WarningBannerText", ""))), ...
    "AxisTransform", string(opts.AxisTransform), ...
    "YFloorApplied", logical(opts.YFloorApplied), ...
    "AggregationMethod", string(opts.AggregationMethod), ...
    "RawRowCount", double(opts.RawRowCount), ...
    "AggregatedRowCount", double(opts.AggregatedRowCount), ...
    "DuplicateRowCount", double(opts.DuplicateRowCount), ...
    "SourceHash", string(opts.SourceHash), ...
    "actual_mime_type", string(opts.ActualMimeType), ...
    "declared_mime_type", string(opts.DeclaredMimeType), ...
    "extension", string(opts.Extension), ...
    "sha256", string(opts.SHA256), ...
    "byte_count", double(opts.ByteCount));
end

function value = localStructField(s, name, fallback)
if isstruct(s) && isfield(s, name)
    value = s.(name);
else
    value = fallback;
end
end

function value = localDefault(candidate, fallback)
if isstring(candidate) || ischar(candidate)
    if strlength(string(candidate)) == 0
        value = fallback;
    else
        value = candidate;
    end
elseif isempty(candidate)
    value = fallback;
else
    value = candidate;
end
end

function value = localResolveVisualValidity(opts, stats)
value = localDefault(opts.VisualValidity, localStructField(stats, "VisualValidity", ""));
value = lower(string(value));
if strlength(value) > 0
    return;
end
renderStatus = lower(string(localDefault(opts.PlotRenderStatus, localStructField(stats, "PlotRenderStatus", ""))));
countsAsReal = logical(localDefault(opts.CountsAsRealPlot, localStructField(stats, "CountsAsRealPlot", false)));
isUnavailable = logical(localDefault(opts.IsUnavailableCard, localStructField(stats, "IsUnavailableCard", false)));
if countsAsReal && contains(renderStatus, "rendered")
    value = "real_lls_evidence";
elseif contains(renderStatus, "diagnostic")
    value = "diagnostic_only";
elseif contains(renderStatus, "stale")
    value = "invalid_stale";
elseif isUnavailable || contains(renderStatus, "suppressed") || contains(renderStatus, "unavailable")
    value = "unavailable";
else
    value = "unavailable";
end
end
