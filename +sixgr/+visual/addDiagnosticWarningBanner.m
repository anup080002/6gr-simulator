function addDiagnosticWarningBanner(figHandle, message)
%ADDDIAGNOSTICWARNINGBANNER Add a visible diagnostic-only warning banner.

if nargin < 2 || strlength(string(message)) == 0
    message = "DIAGNOSTIC ONLY - not counted as real LLS evidence";
end
try
    annotation(figHandle, "textbox", [0.01 0.945 0.98 0.045], ...
        "String", char(string(message)), ...
        "Interpreter", "none", ...
        "HorizontalAlignment", "center", ...
        "VerticalAlignment", "middle", ...
        "FontWeight", "bold", ...
        "FontSize", 9, ...
        "Color", [0.36 0.22 0.00], ...
        "BackgroundColor", [1.00 0.93 0.70], ...
        "EdgeColor", [0.84 0.55 0.10], ...
        "FitBoxToText", "off");
catch
end
end
