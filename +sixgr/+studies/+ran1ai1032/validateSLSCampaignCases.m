function validation = validateSLSCampaignCases(cases, cfg)
%VALIDATESLSCAMPAIGNCASES Fail closed on unpaired or unphysical SLS cases.

arguments
    cases table
    cfg struct
end

required = ["CaseID","CasePairKey","BasePairKey","Scenario", ...
    "Population","TargetRUPercent","IndependentDropID","ComparatorID", ...
    "UETxChains","SpatialMode","PowerCase","InitialRank", ...
    "ComparatorMaxRank","EffectiveMaxRank","AdaptiveRank", ...
    "GeometrySeed","ShadowSeed","TrafficSeed", ...
    "AntennaOrientationSeed","SchedulerSeed","PropagationSeed", ...
    "ArrivalStreamID","SeedBundleID","ConfigDelta", ...
    "ExecutionParameters","ConfigDeltaSHA256"];
required = [required, "ExecutionStatus", "PrimaryResultEligible", ...
    "ExecutionBlocker","PlannedExecutionArchitecture","PlannedResultClassification"];
if ~all(ismember(required, string(cases.Properties.VariableNames)))
    error("sixgr:ran1ai1032:IncompleteSLSCaseTable", ...
        "SLS case table is missing one or more required identity, rank or seed columns.");
end
assert(all(cases.PlannedExecutionArchitecture==string(cfg.sls.execution.architecture)) && ...
    all(cases.PlannedResultClassification==string(cfg.sls.execution.result_classification)), ...
    'sixgr:ran1ai1032:SLSArchitecture','Planned SLS architecture/classification differs from the approved config.');
if numel(unique(cases.CaseID)) ~= height(cases)
    error("sixgr:ran1ai1032:DuplicateSLSCaseID", ...
        "Every expanded SLS case must have a unique CaseID.");
end
if any(cases.ExecutionStatus ~= ...
        "blocked_pending_lls_adaptive_calibration") || ...
        any(cases.PrimaryResultEligible) || ...
        any(cases.ExecutionBlocker ~= ...
        "missing_executed_phy_truth_fixed_mcs_calibration")
    error("sixgr:ran1ai1032:UncalibratedSLSCaseNotBlocked", ...
        ["Adaptive SLS planning rows must remain non-executable and " ...
        "ineligible for primary results until executed-PHY fixed-MCS " ...
        "calibration has passed."]);
end

expectedComparators = sort(string({cfg.sls.comparators.id}).');
seedNames = ["GeometrySeed","ShadowSeed","TrafficSeed", ...
    "AntennaOrientationSeed","SchedulerSeed","PropagationSeed"];
deploymentIDs = string({cfg.sls.deployments.id});
deploymentBases = cell(numel(cfg.sls.deployments), 1);
for deploymentIndex = 1:numel(cfg.sls.deployments)
    deployment = cfg.sls.deployments(deploymentIndex);
    topology = sixgr.studies.ran1ai1032.buildHexWraparoundTopology( ...
        double(cfg.sls.sites), double(cfg.sls.sectors_per_site), ...
        double(deployment.inter_site_distance_m));
    deploymentBases{deploymentIndex} = topology.TranslationVectors_m;
end
pairKeys = unique(cases.CasePairKey, "stable");
for i = 1:numel(pairKeys)
    rows = cases.CasePairKey == pairKeys(i);
    if ~isequal(sort(cases.ComparatorID(rows)), expectedComparators)
        error("sixgr:ran1ai1032:IncompleteExpandedComparatorPair", ...
            "Expanded pair %s must contain exactly one row for S0--S5.", pairKeys(i));
    end
    immutable = ["BasePairKey","Scenario","Population", ...
        "IndependentDropID","UETxChains","SpatialMode","PowerCase", ...
        "ArrivalStreamID","SeedBundleID"];
    for name = immutable
        if numel(unique(cases.(name)(rows))) ~= 1
            error("sixgr:ran1ai1032:ExpandedPairIdentityChanged", ...
                "Expanded pair %s changes immutable identity field %s.", ...
                pairKeys(i), name);
        end
    end
    for name = seedNames
        if numel(unique(cases.(name)(rows))) ~= 1
            error("sixgr:ran1ai1032:ExpandedPairSeedChanged", ...
                "Expanded pair %s changes paired seed %s.", pairKeys(i), name);
        end
    end
end

if any(cases.InitialRank ~= 1) || any(~cases.AdaptiveRank) || ...
        any(cases.EffectiveMaxRank > cases.UETxChains) || ...
        any(cases.EffectiveMaxRank > cases.ComparatorMaxRank)
    error("sixgr:ran1ai1032:InvalidExpandedRankPolicy", ...
        "Every SLS case must start at rank one, adapt rank, and respect UE ports and comparator rank caps.");
end

% The SystemLevelRunner accepts paired component seeds through
% params.SeedBundle. Verify that every emitted execution parameter bundle
% is byte-for-byte consistent with the authoritative case columns.
for rowIndex = 1:height(cases)
    params = cases.ExecutionParameters{rowIndex};
    delta = cases.ConfigDelta{rowIndex};
    assert(isequaln(sixgr.util.structGet(delta,'study.sls_execution',struct()),cfg.sls.execution), ...
        'sixgr:ran1ai1032:SLSArchitecture','Case delta changes the calibrated SLS execution contract.');
    if ~(isstruct(params) && isscalar(params) && ...
            isfield(params, "SeedBundle") && isstruct(params.SeedBundle))
        error("sixgr:ran1ai1032:MissingExecutionSeedBundle", ...
            "Case %s lacks its executable params.SeedBundle binding.", ...
            cases.CaseID(rowIndex));
    end
    bundle = params.SeedBundle;
    for name = seedNames
        if ~isfield(bundle, name) || ...
                double(bundle.(name)) ~= double(cases.(name)(rowIndex))
            error("sixgr:ran1ai1032:ExecutionSeedBundleMismatch", ...
                "Case %s execution seed %s differs from the paired plan.", ...
                cases.CaseID(rowIndex), name);
        end
    end
    if ~isfield(params, "FWAPopulationSpec") || ...
            string(params.FWAPopulationSpec.ProfileID) ~= cases.Population(rowIndex) || ...
            double(params.FWAPopulationSpec.PopulationSeed) ~= ...
            double(cases.GeometrySeed(rowIndex)) || ...
            double(params.FWAPopulationSpec.ExpectedUECount) ~= ...
            double(cfg.sls.cells) * double(cfg.sls.ues_per_cell)
        error("sixgr:ran1ai1032:ExecutionPopulationBindingMismatch", ...
            "Case %s lacks its exact paired FWA population binding.", ...
            cases.CaseID(rowIndex));
    end
    deploymentIndex = find(deploymentIDs == cases.Scenario(rowIndex), ...
        1, "first");
    if isempty(deploymentIndex)
        error("sixgr:ran1ai1032:MissingDeploymentDefinition", ...
            "Scenario %s has no deployment definition.", ...
            cases.Scenario(rowIndex));
    end
    expectedBasis = deploymentBases{deploymentIndex};
    if ~isfield(delta, "scenario") || ...
            ~isfield(delta.scenario, "layout") || ...
            ~isfield(delta.scenario.layout, "wraparoundMode") || ...
            string(delta.scenario.layout.wraparoundMode) ~= ...
            "hex_cluster_min_image" || ...
            ~isfield(delta.scenario.layout, ...
            "wraparoundTranslationVectors_m") || ...
            ~isequal(double(delta.scenario.layout.wraparoundTranslationVectors_m), ...
            expectedBasis) || ...
            ~isfield(delta.scenario, "geometry") || ...
            ~isequal(double(delta.scenario.geometry.wraparoundTranslationVectors_m), ...
            expectedBasis)
        error("sixgr:ran1ai1032:ExecutionWraparoundBindingMismatch", ...
            ["Case %s does not bind the finite seven-site cluster " ...
            "translation basis into its runtime config delta."], ...
            cases.CaseID(rowIndex));
    end
end
s4 = cases.ComparatorID == "S4";
s5 = cases.ComparatorID == "S5";
if any(cases.ComparatorMaxRank(s4) ~= 2) || ...
        any(cases.ComparatorMaxRank(s5) ~= 4) || ...
        any(cases.EffectiveMaxRank(s4) ~= min(2, cases.UETxChains(s4))) || ...
        any(cases.EffectiveMaxRank(s5) ~= min(4, cases.UETxChains(s5)))
    error("sixgr:ran1ai1032:ExpandedRankComparatorMismatch", ...
        "S4 must preserve its rank-2 cap and S5 its rank-4 cap, subject only to the physical UE-port cap.");
end

expectedCasePairs = 2 * 2 * 3 * double(cfg.sls.independent_paired_drops) * ...
    numel(cfg.sls.ue_tx_chain_cases) * numel(cfg.sls.spatial_modes) * ...
    numel(cfg.sls.ue_power_cases);
if numel(pairKeys) ~= expectedCasePairs || ...
        height(cases) ~= expectedCasePairs * numel(expectedComparators)
    error("sixgr:ran1ai1032:IncompleteSLSCaseMatrix", ...
        "Expanded SLS matrix does not cover every configured axis.");
end

validation = struct( ...
    "Status", "PASS", ...
    "CasePairCount", numel(pairKeys), ...
    "CaseCount", height(cases), ...
    "ComparatorCount", numel(expectedComparators), ...
    "PairingUnit", "expanded_case_pair", ...
    "RankPolicy", "adaptive_with_physical_port_cap");
end
