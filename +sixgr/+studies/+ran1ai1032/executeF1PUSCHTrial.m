function [out,retained]=executeF1PUSCHTrial(cfg,study,attempt)
%EXECUTEF1PUSCHTRIAL Independent-TB experiment over production PHY and channel.
% The receiver gets configured allocation/coding only. No TX bits, channel
% truth, injected noise variance, or transmitted UCI layout enter decoding.
arguments
    cfg struct
    study struct
    attempt (1,1) struct = struct()
end
rv=double(sixgr.util.structGet(attempt,'RV',0));
validateattributes(rv,{'numeric'},{'scalar','integer','>=',0,'<=',3});
payload=sixgr.util.structGet(attempt,'TransportBlock',[]);
prior=sixgr.util.structGet(attempt,'SoftBuffer',[]);
priorLayout=sixgr.util.structGet(attempt,'CodingLayout',struct());
if ~isempty(prior)
    assert(~isempty(payload) && isfield(attempt,'TransportBlockSHA256') && ...
        string(attempt.TransportBlockSHA256)==string(sixgr.util.sha256Hex(uint8(payload(:)))), ...
        'sixgr:ran1ai1032:F1HARQPayload','Retained HARQ payload must preserve its original identity.');
end
old=rng; restore=onCleanup(@()rng(old)); %#ok<NASGU>
rng(double(cfg.run.seed),'twister');
carrier=sixgr.phy.grid.makeCarrier(cfg);
txTransport=sixgr.phy.research.configuredPUSCHTransport(cfg,carrier);
nt=double(cfg.scenario.ue.nTxAnt); nr=double(cfg.scenario.bs.nRxAnt);
rank=double(cfg.phy.pusch.nLayers); rate=double(cfg.phy.pusch.codeRate);
[tx,txInfo]=sixgr.phy.ul.PUSCH_Tx(cfg,'Carrier',carrier, ...
    'ResearchTransport',txTransport,'TargetCodeRate',rate,'RV',rv, ...
    'TransportBlockBits',payload, ...
    'InitialIMCSPerCodeword',cfg.phy.pusch.mcsIndex,'NumTxAnt',nt);
assert(size(tx.Waveform,2)==nt && ~isempty(tx.Grid), ...
    'sixgr:ran1ai1032:F1Transmitter','Actual TX grid/waveform must preserve every physical chain.');
assert(string(study.lls.execution.tx_power_normalization)== ...
    "constant_total_configured_grid_re_energy", ...
    'sixgr:ran1ai1032:F1PowerPolicy','Declare a constant-total-UE grid-energy policy.');
target=double(study.lls.execution.normalized_total_ue_grid_re_energy);
validateattributes(target,{'numeric'},{'scalar','positive','finite'});
% TX-only normalization includes actual data, DMRS and their port mapping.
% One scalar multiplies the complete waveform; relative RS powers survive.
before=sum(abs(double(tx.Grid)).^2,'all')/(size(tx.Grid,1)*size(tx.Grid,2));
assert(isfinite(before) && before>0,'sixgr:ran1ai1032:F1TransmitEnergy','TX grid is empty.');
scale=sqrt(target/before);
wave=tx.Waveform*scale;
after=sum(abs(double(tx.Grid).*scale).^2,'all')/(size(tx.Grid,1)*size(tx.Grid,2));
assert(abs(after-target)<=1e-10*target,'sixgr:ran1ai1032:F1PowerClosure', ...
    'Actual total transmit grid power does not match its configured budget.');
[wave,txRF]=sixgr.studies.ran1ai1032.applyF1TransmitRF(wave,cfg,tx.OFDM.SampleRate);
state=sixgr.channel.ChannelFactory.createRuntimeChannelState(cfg,'UL','UEIndex',1,'ServingCell',1);
state.TargetUEIndex=1; state.TargetServingCell=1;
state=sixgr.channel.ChannelFactory.materializeRuntimeChannelState( ...
    state,cfg,wave,txInfo,'NumTxAnt',nt,'NumRxAnt',nr);
% Flush the actual channel filter. Tail length is channel execution evidence,
% not a channel estimate or a receiver timing offset.
tail=max(0,ceil(double(state.ChannelPadSamples)))+max(0,ceil(double(state.ChannelTrimSamples)));
wave=[wave;zeros(tail,nt,'like',wave)];
cfg.rf.rx.additiveEVMStudy.observationSamples=size(wave,1);
owner=sixgr.truth.SharedWaveformPhysicalRuntime(tx.OFDM.SampleRate,0,1);
owner.addTransmitter('ue',cfg,'UL',nt,false);
owner.addReceiver('gnb',cfg,'UL',nr,false);
owner.addLink('f1_physical_link','ue','gnb',state,cfg);
input=struct('ID',"ue",'Chunk',sixgr.phy.waveform.WaveformChunk(wave,0));
[outputs,physical]=owner.process(input,0,size(wave,1),[]);
capture=outputs(string({outputs.ID})=="gnb:post_rf");
assert(isscalar(capture) && size(capture.Chunk.Samples,2)==nr, ...
    'sixgr:ran1ai1032:F1ReceiverDimensions','Physical receive branches disagree with the case.');
rxTransport=sixgr.phy.research.configuredPUSCHTransport(cfg,carrier);
[~,allocation]=nrPUSCHIndices(carrier,rxTransport.Geometry);
tbs=nrTBS(char(cfg.phy.pusch.modulation),rank,numel(cfg.phy.pusch.prbSet), ...
    allocation.NREPerPRB,rate,cfg.phy.pusch.xOverhead);
assert(tbs==tx.TransportBlockSize,'sixgr:ran1ai1032:F1ExactTBS','Independent exact TBS disagrees with TX.');
context=sixgr.phy.ul.pusch.PUSCHUCIReceiveContext(struct( ...
    'ObservationID',"F1_seed_"+string(cfg.run.seed),'ConfigurationEpoch',1, ...
    'AssignmentDigest',string(cfg.meta.f1StudyCaseID),'HARQMappingDigest',"", ...
    'HARQACKBitCount',0,'ConfiguredGrantUCIBitCount',0, ...
    'CSIReportConfigID',"",'CSIConfigurationEpoch',NaN));
rx=sixgr.phy.ul.PUSCH_Rx(capture.Chunk.Samples,cfg,'Carrier',carrier, ...
    'ResearchTransport',rxTransport,'TransportBlockSize',tbs, ...
    'TargetCodeRate',rate,'RV',rv,'InitialIMCSPerCodeword',cfg.phy.pusch.mcsIndex, ...
    'HARQSoftBufferLLR',prior,'HARQSoftBufferLayout',priorLayout, ...
    'UCIReceiveContext',context);
assert(isempty(prior) || (rx.HARQSoftCombiningApplied && rx.HARQSoftCombiningPositionAware), ...
    'sixgr:ran1ai1032:F1HARQCombining','A retransmission must use compatible position-aware mother-code combining.');
assert(rx.ChannelEstimateAvailable && rx.EqualizationAvailable && ...
    isfield(rx,'TransportBlock') && numel(rx.TransportBlock)==tbs, ...
    'sixgr:ran1ai1032:F1ReceiverExecution','A completed practical estimator/decoder is required.');
bitsWrong=nnz(int8(rx.TransportBlock(:))~=int8(tx.TransportBlock(:)));
crc=~logical(rx.CRCError);
assert(~crc || bitsWrong==0,'sixgr:ran1ai1032:F1UndetectedTBError', ...
    'CRC passed while independent transmitted-payload scoring found errors.');
equalized=rx.LayerEqualizedSymbolsForEvidence;
reference=tx.PUSCHLayerSymbols;
assert(isequal(size(equalized),size(reference)), ...
    'sixgr:ran1ai1032:F1EVMPlane','Exact layer-plane EVM requires identical symbol identities.');
evm=sqrt(sum(abs(double(equalized)-double(reference)).^2,'all')/ ...
    sum(abs(double(reference)).^2,'all'));
replay=physical.RX.Replay;
configured=double(cfg.channel.snr_dB);
appliedDoppler=double(cfg.channel.doppler_Hz);
if string(cfg.channel.model)=="AWGN", appliedDoppler=0; end
assert(abs(double(replay.GridNoiseVariance)-double(cfg.channel.awgnReferenceREEnergy)*10^(-configured/10)) ...
    <1e-10*double(replay.GridNoiseVariance), ...
    'sixgr:ran1ai1032:F1NoiseBinding','Shared physical receiver applied incorrect reference noise.');
r=struct('Seed',double(cfg.run.seed),'MCS',double(cfg.phy.pusch.mcsIndex), ...
    'PRBs',numel(cfg.phy.pusch.prbSet),'Layers',rank, ...
    'Modulation',string(cfg.phy.pusch.modulation),'TargetCodeRate',rate, ...
    'TBSize_bits',double(tbs),'CRCPass',crc,'DecoderIterations',double(rx.DecoderIterations), ...
    'EVM_rms',evm,'NMSE_dB',NaN,'NMSEStatus',"unavailable_no_retained_channel_truth_reference", ...
    'MeasuredSINR_dB',double(rx.PostEqSINR_dB),'ConditionNumber_dB',NaN, ...
    'NumRxAntennas',nr,'NumTxPorts',nt,'BitErrors',bitsWrong,'BitsCompared',double(tbs), ...
    'GoodBits',double(tbs)*double(crc),'OfferedBits',double(tbs), ...
    'NumCodeBlocks',double(rx.NumCodeBlocks),'BaseGraph',double(tx.BaseGraph), ...
    'EncodedBits',double(numel(tx.Codeword)),'RateMatchedBits',double(tx.G), ...
    'DataRECount',double(tx.ResourceAccounting.LayerDataRE), ...
    'DMRSRECount',double(numel(nrPUSCHDMRSIndices(carrier,rxTransport.Geometry))), ...
    'PTRSRECount',double(numel(tx.PTRSIndices)),'ConfiguredSNR_dB',configured,'AppliedAWGNSNR_dB',double(replay.AppliedAWGNSNR_dB), ...
    'NoiseVariance',double(rx.NoiseVar),'NoiseVarianceSource',string(rx.NoiseVarSource), ...
    'ExecutionBackend',"canonical_shared_pusch_waveform_chain", ...
    'ChannelModel',string(cfg.channel.model),'DopplerHz',appliedDoppler, ...
    'ConfiguredDopplerHz',double(cfg.channel.doppler_Hz), ...
    'TBSInputNREPerPRB',double(allocation.NREPerPRB),'TBSInputXOverhead',double(cfg.phy.pusch.xOverhead), ...
    'TBSInputSource',"independently_configured_nrTBS", ...
    'MeasuredTrialSINRSource',string(rx.PostEqSINRSource), ...
    'ChannelEstimateAvailable',logical(rx.ChannelEstimateAvailable), ...
    'EqualizationAvailable',logical(rx.EqualizationAvailable),'Notes',"independent_first_transmission_no_UCI", ...
    'PowerNormalizationPolicy',string(study.lls.execution.tx_power_normalization), ...
    'PowerNormalizationSource',"actual_transmitted_grid_total_energy_before_channel", ...
    'PowerNormalizationGridMeanEnergyPerRE',after,'TransmitGridEnergyBeforeNormalization',before, ...
    'AppliedTransmitAmplitudeScale',scale,'AppliedGridNoiseVariance',double(replay.GridNoiseVariance), ...
    'SampleNoiseVariance',double(replay.SampleNoiseVariance));
% These RF measurements are from the same transmitted samples and receive
% observation that underwent practical estimation, LDPC and CRC above.
for field=string(fieldnames(txRF)).'
    r.(field)=txRF.(field);
end
r.ConfiguredRXEVMPercent=double(replay.AdditiveReceiverEVM.ConfiguredPercent);
r.MeasuredRXEVMPercent=double(replay.AdditiveReceiverEVM.MeasuredPercent);
r.RXEVMReferenceSource=string(replay.AdditiveReceiverEVM.ReferenceSource);
r.AppliedCFOHz=double(physical.TX.Replay.InjectedCFO_Hz);
r.PhaseNoiseApplied=logical(physical.TX.Replay.PhaseNoiseApplied);
r.PhaseNoiseProfileID=""; r.PhaseNoiseProfileSource="";
if logical(cfg.rf.studyBranch.phase_noise_enabled)
    r.PhaseNoiseProfileID=string(cfg.rf.studyBranch.phase_noise_profile.profile_id);
    r.PhaseNoiseProfileSource=string(cfg.rf.studyBranch.phase_noise_profile_source);
end
r.RFClassification=string(cfg.meta.f1RFClassification);
r.RFProfileID=string(cfg.meta.f1RFProfileID);
for field=["PTRSConfiguredEnabled","PTRSCPECorrectionConfigured","PTRSCPECorrectionApplied", ...
        "PTRSCPECorrectionSymbols","PTRSMeanCPE_deg","PTRSCPECorrectionStatus"]
    value=rx.(field);
    if ischar(value), value=string(value); end
    r.(field)=value;
end
r.PostRFMeanTotalTransmitSamplePower=mean(sum(abs(double(wave)).^2,2));
r.NominalPreCapGridReferenceEnergy=after;
r.RV=rv;
r.TransportBlockSHA256=string(sixgr.util.sha256Hex(uint8(tx.TransportBlock(:))));
r.HARQSoftCombiningApplied=logical(rx.HARQSoftCombiningApplied);
r.HARQSoftCombiningPositionAware=logical(rx.HARQSoftCombiningPositionAware);
if ~isempty(prior), r.Notes="independent_attempt_channel_with_retained_HARQ_soft_buffer_no_UCI"; end
out=struct('Skipped',false,'ExecutionBackend',r.ExecutionBackend,'TrialTable',struct2table(r));
if nargout>1
    retained=struct('TransportBlock',tx.TransportBlock,'TransportBlockSHA256',r.TransportBlockSHA256, ...
        'SoftBuffer',rx.HARQSoftBuffer,'CodingLayout',rx.CodingLayout);
end
end
