function out = validateAdaptiveCalibrationTable(T, cfg)
%VALIDATEADAPTIVECALIBRATIONTABLE Gate adaptive H0--H3 SLS selection.
%
% The table must be derived from executed, waveform-backed LLS evidence.
% A guessed CQI extension or analytic Shannon threshold is not accepted.

arguments
    T table
    cfg struct
end
required = ["EntryID","MCSIndex","Qm","TargetCodeRateX1024","Rank", ...
    "BLERTarget","RequiredSINRdB","SourceCaseID","SourceChannel", ...
    "TransportBlockCount","ErrorCount","Censored","ExecutionBackend", ...
    "SourceClassification","DelaySpread_ns","AntennaCaseID", ...
    "TxChains","RxChains","RFBranch","RFProfileID","PowerPlane"];
if any(~ismember(required, string(T.Properties.VariableNames)))
    error("sixgr:ran1ai1032:CalibrationSchema", ...
        "Adaptive calibration is missing mandatory waveform-evidence columns.");
end
if isempty(T)
    error("sixgr:ran1ai1032:CalibrationEmpty", ...
        "Adaptive 1024-QAM SLS cannot run without LLS calibration rows.");
end

targetBLER = double(cfg.sls.adaptive_selection.target_first_transmission_bler);
expected = sixgr.studies.ran1ai1032.MCSCatalog.optionA();
h = expected(ismember(expected.entry_id, ["H0";"H1";"H2";"H3"]), :);
requiredRanks = double(cfg.sls.adaptive_selection.required_calibration_ranks(:));
groupFields=["SourceChannel","DelaySpread_ns","AntennaCaseID", ...
    "TxChains","RxChains","RFBranch","RFProfileID","PowerPlane"];
groups=unique(T(:,groupFields),'rows','stable');
for groupIndex=1:height(groups)
    groupMask=true(height(T),1);
    for key=string(groupFields)
        groupMask=groupMask & T.(key)==groups.(key)(groupIndex);
    end
    g=groups(groupIndex,:);
    antenna=cfg.lls.antenna_cases(string({cfg.lls.antenna_cases.id})==string(g.AntennaCaseID));
    channel=cfg.lls.channels(string({cfg.lls.channels.profile})==string(g.SourceChannel));
    if numel(antenna)~=1 || numel(channel)~=1 || ...
            g.TxChains~=antenna.tx_chains || g.RxChains~=antenna.rx_chains || ...
            g.DelaySpread_ns~=channel.delay_spread_ns || ...
            any(T.Rank(groupMask)>min(g.TxChains,g.RxChains)) || ...
            strlength(strtrim(string(g.RFBranch)))==0 || ...
            strlength(strtrim(string(g.RFProfileID)))==0 || ...
            strlength(strtrim(string(g.PowerPlane)))==0
        error('sixgr:ran1ai1032:CalibrationPhysicalIdentity', ...
            'Each threshold must retain a configured channel, delay spread, antenna and power-plane identity.');
    end
for rank = requiredRanks(requiredRanks<=min(g.TxChains,g.RxChains)).'
    for i = 1:height(h)
        rows = groupMask & string(T.EntryID) == h.entry_id(i) & double(T.Rank) == rank;
        if nnz(rows) ~= 1
            error("sixgr:ran1ai1032:CalibrationCoverage", ...
                "Exactly one calibration row per physical channel/antenna/RF group is required for %s rank %d.", ...
                h.entry_id(i), rank);
        end
        r = T(rows,:);
        if double(r.MCSIndex) ~= h.indication_index(i) || ...
                double(r.Qm) ~= h.Qm(i) || ...
                abs(double(r.TargetCodeRateX1024) - ...
                h.target_code_rate_x1024(i)) > 1e-12
            error("sixgr:ran1ai1032:CalibrationEntryIdentity", ...
                "Calibration changed the immutable meaning of %s.", h.entry_id(i));
        end
    end
end
end

backend = lower(strtrim(string(T.ExecutionBackend)));
classification = lower(strtrim(string(T.SourceClassification)));
if any(abs(double(T.BLERTarget) - targetBLER) > 1e-12) || ...
        any(~isfinite(double(T.RequiredSINRdB))) || ...
        any(double(T.TransportBlockCount) < ...
        double(cfg.statistics.minimum_transport_blocks_per_point)) || ...
        any(double(T.ErrorCount) < double(cfg.statistics.minimum_errors_per_point)) || ...
        any(logical(T.Censored)) || ...
        any(~contains(backend, "waveform")) || ...
        any(contains(backend, ["proxy","lut","synthetic","fallback"])) || ...
        any(classification ~= "executed_phy_truth") || ...
        any(strlength(strtrim(string(T.SourceCaseID))) == 0) || ...
        any(strlength(strtrim(string(T.SourceChannel))) == 0)
    error("sixgr:ran1ai1032:CalibrationEvidenceRejected", ...
        ["Adaptive calibration requires uncensored %.3f first-TX BLER " + ...
        "thresholds with >=%d TBs, >=%d errors and executed waveform truth."], ...
        targetBLER, double(cfg.statistics.minimum_transport_blocks_per_point), ...
        double(cfg.statistics.minimum_errors_per_point));
end

out = struct("Ok", true, "RowCount", height(T), "PhysicalGroupCount",height(groups), ...
    "ValidationScope","threshold_schema_and_statistics_not_source_artifact_authentication", ...
    "TargetFirstTransmissionBLER", targetBLER, ...
    "RequiredRanks", requiredRanks, ...
    "SelectionAuthority", "LLS_measured_required_SINR_thresholds", ...
    "Status", "PASS");
end
