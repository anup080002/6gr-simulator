function out = extractF1CalibrationThresholds(curves, study)
%EXTRACTF1CALIBRATIONTHRESHOLDS Retain distinct physical-case BLER crossings.
% Never merge channel profiles, arrays, ranks or RF branches into a single
% threshold. Configured reference SNR and observed receiver SINR are separate.
arguments
    curves table
    study struct
end
out=table();
if isempty(curves), return; end
required=["CaseID","EntryID","ChannelProfile","DelaySpread_ns","AntennaCaseID", ...
    "Rank","TxChains","RxChains","Qm","TargetCodeRateX1024","ConfiguredSNR_dB", ...
    "MeanMeasuredSINR_dB","BLER","StatisticsComplete","Censored","TransportBlockCount", ...
    "ErrorCount","ExecutionBackend","SourceClassification","RFBranch","RFProfileID","PowerPlane"];
assert(all(ismember(required,string(curves.Properties.VariableNames))), ...
    'sixgr:ran1ai1032:F1CurveSchema','Calibration curves lack physical evidence identity.');
target=double(study.sls.adaptive_selection.target_first_transmission_bler);
entries=sixgr.studies.ran1ai1032.MCSCatalog.optionA();
for id=unique(string(curves.CaseID),'stable').'
    T=sortrows(curves(string(curves.CaseID)==id,:),'ConfiguredSNR_dB');
    for key=["EntryID","ChannelProfile","DelaySpread_ns","AntennaCaseID","Rank", ...
            "TxChains","RxChains","Qm","TargetCodeRateX1024","RFBranch","RFProfileID","PowerPlane"]
        assert(numel(unique(T.(key)))==1,'sixgr:ran1ai1032:F1MixedPhysicalCase', ...
            'A source CaseID cannot contain different %s values.',key);
    end
    assert(numel(unique(T.ConfiguredSNR_dB))==height(T), ...
        'sixgr:ran1ai1032:F1DuplicatePoint','Each case/SNR must be one pooled trial population.');
    admissible=logical(T.StatisticsComplete) & ~logical(T.Censored) & ...
        T.TransportBlockCount>=double(study.statistics.minimum_transport_blocks_per_point) & ...
        T.ErrorCount>=double(study.statistics.minimum_errors_per_point) & ...
        string(T.SourceClassification)=="executed_phy_truth" & ...
        contains(string(T.ExecutionBackend),'waveform') & ...
        ~contains(lower(string(T.ExecutionBackend)),["proxy","lut","synthetic","fallback"]);
    crossing=find(T.BLER(1:end-1)>target & T.BLER(2:end)<=target & ...
        admissible(1:end-1) & admissible(2:end));
    if numel(crossing)~=1, continue; end
    i=crossing; j=i+1;
    % A coarse-only bracket is useful progress but is not a refined result.
    if T.ConfiguredSNR_dB(j)-T.ConfiguredSNR_dB(i)>double(study.statistics.refinement_step_db)+1e-9
        continue;
    end
    if any(~isfinite(T.MeanMeasuredSINR_dB([i j]))) || ...
            T.MeanMeasuredSINR_dB(j)<=T.MeanMeasuredSINR_dB(i)
        continue;
    end
    weight=(T.BLER(i)-target)/(T.BLER(i)-T.BLER(j));
    reference=T.ConfiguredSNR_dB(i)+weight*(T.ConfiguredSNR_dB(j)-T.ConfiguredSNR_dB(i));
    measured=T.MeanMeasuredSINR_dB(i)+weight*(T.MeanMeasuredSINR_dB(j)-T.MeanMeasuredSINR_dB(i));
    entry=entries(entries.entry_id==string(T.EntryID(1)),:);
    assert(height(entry)==1 && entry.Qm==T.Qm(1) && ...
        entry.target_code_rate_x1024==T.TargetCodeRateX1024(1), ...
        'sixgr:ran1ai1032:F1EntryIdentity','Curve changed immutable MCS meaning.');
    r=table(string(T.EntryID(1)),double(entry.indication_index),T.Qm(1), ...
        T.TargetCodeRateX1024(1),T.Rank(1),target,measured,reference,id, ...
        string(T.ChannelProfile(1)),T.DelaySpread_ns(1),string(T.AntennaCaseID(1)), ...
        T.TxChains(1),T.RxChains(1),min(T.TransportBlockCount([i j])), ...
        min(T.ErrorCount([i j])),false,string(T.ExecutionBackend(1)), ...
        "executed_phy_truth",string(T.RFBranch(1)),string(T.RFProfileID(1)),string(T.PowerPlane(1)), ...
        T.ConfiguredSNR_dB(i),T.ConfiguredSNR_dB(j), ...
        T.MeanMeasuredSINR_dB(i),T.MeanMeasuredSINR_dB(j), ...
        "linear_interpolation_of_executed_refined_bracket", ...
        'VariableNames',{'EntryID','MCSIndex','Qm','TargetCodeRateX1024','Rank', ...
        'BLERTarget','RequiredSINRdB','RequiredReferenceSNRdB','SourceCaseID', ...
        'SourceChannel','DelaySpread_ns','AntennaCaseID','TxChains','RxChains', ...
        'TransportBlockCount','ErrorCount','Censored','ExecutionBackend', ...
        'SourceClassification','RFBranch','RFProfileID','PowerPlane','BracketReferenceSNRLow_dB', ...
        'BracketReferenceSNRHigh_dB','BracketMeasuredSINRLow_dB', ...
        'BracketMeasuredSINRHigh_dB','ThresholdMethod'});
    out=[out;r]; %#ok<AGROW>
end
end
