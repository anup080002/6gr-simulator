function cfg = validateStudyConfig(cfg)
%VALIDATESTUDYCONFIG Fail-closed validation for the 6GR AI 10.3.2 study.

required = ["schema_version","study","carrier","statistics","lls", ...
    "harq","link_adaptation","rf","representations","sls","outputs"];
for name = required
    if ~isfield(cfg, name)
        error("sixgr:ran1ai1032:MissingConfigSection", ...
            "Required configuration section '%s' is missing.", name);
    end
end
if string(cfg.schema_version) ~= "sixgr.ran1.ai_10_3_2_modulation/v1"
    error("sixgr:ran1ai1032:BadStudySchema", ...
        "Unsupported AI 10.3.2 study schema.");
end
if string(cfg.study.generation_label) ~= "6GR" || ...
        ~logical(cfg.study.strict) || ~logical(cfg.study.prohibit_fallback) || ...
        ~logical(cfg.study.prohibit_approximate_tbs)
    error("sixgr:ran1ai1032:Strict6GRStudyRequired", ...
        "The campaign must be labelled 6GR and prohibit fallback and approximate TBS.");
end

carrier = cfg.carrier;
localEqual(carrier.frequency_hz, 7e9, "carrier.frequency_hz");
localEqual(carrier.bandwidth_hz, 100e6, "carrier.bandwidth_hz");
localEqual(carrier.scs_khz, 30, "carrier.scs_khz");

stats = cfg.statistics;
localValidateExecution(cfg);
coarse = double(stats.coarse_snr_db(:));
if ~isequal(coarse, (-10:45).') || double(stats.coarse_step_db) ~= 1 || ...
        double(stats.refinement_step_db) ~= 0.1 || ...
        double(stats.minimum_transport_blocks_per_point) < 2000 || ...
        double(stats.minimum_errors_per_point) < 200 || ...
        double(stats.maximum_transport_blocks_per_point) < ...
        double(stats.minimum_transport_blocks_per_point) || ...
        double(stats.confidence_level) ~= 0.95 || ...
        ~logical(stats.preserve_censored_points)
    error("sixgr:ran1ai1032:InvalidStatisticsPolicy", ...
        "Statistics must use -10:45 dB coarse points, 0.1 dB refinement, >=2000 TB, >=200 errors, and censored 95%% bounds.");
end

channels = string({cfg.lls.channels.profile});
delays = double([cfg.lls.channels.delay_spread_ns]);
requiredChannels = ["AWGN","CDL-A","CDL-B","CDL-C","TDL-A","TDL-D"];
if ~all(ismember(requiredChannels, channels)) || ...
        delays(channels == "CDL-A") ~= 100 || ...
        delays(channels == "CDL-B") ~= 30 || ...
        delays(channels == "CDL-C") ~= 300 || ...
        delays(channels == "TDL-A") ~= 30 || ...
        delays(channels == "TDL-D") ~= 30
    error("sixgr:ran1ai1032:InvalidChannelMatrix", ...
        "The mandatory AWGN/CDL/TDL profiles and delay spreads are incomplete.");
end

mobility = cfg.lls.mobility;
expectedDoppler = 7e9 * (0.3 / 3.6) / 299792458;
if abs(double(mobility.fwa_speed_kmh) - 0.3) > 1e-12 || ...
        abs(double(mobility.derived_doppler_hz) - expectedDoppler) > 1e-9 || ...
        double(mobility.high_doppler_sensitivity_hz) ~= 200
    error("sixgr:ran1ai1032:InconsistentDoppler", ...
        "FWA Doppler must be derived from 7 GHz and 0.3 km/h; 200 Hz is a separate sensitivity.");
end

if ~logical(cfg.lls.practical_channel_estimation_main) || ...
        ~logical(cfg.lls.perfect_csi_upper_bound_only) || ...
        string(cfg.lls.primary_equalizer) ~= "LMMSE" || ...
        string(cfg.lls.interference_equalizer) ~= "MMSE-IRC" || ...
        string(cfg.lls.demapper) ~= "max-log"
    error("sixgr:ran1ai1032:InvalidReceiverPolicy", ...
        "Main results require practical CE, LMMSE, max-log, and MMSE-IRC for explicit interference.");
end
if ~isfield(cfg.lls, "pairing_base_seed") || ...
        ~(isscalar(cfg.lls.pairing_base_seed) && ...
        isfinite(double(cfg.lls.pairing_base_seed)) && ...
        double(cfg.lls.pairing_base_seed) >= 1 && ...
        double(cfg.lls.pairing_base_seed) == fix(double(cfg.lls.pairing_base_seed)))
    error("sixgr:ran1ai1032:InvalidLLSPairingSeed", ...
        "LLS common-random-number pairing requires a positive integer base seed.");
end

if double(cfg.lls.ldpc.maximum_iterations) ~= 50 || ...
        ~logical(cfg.lls.ldpc.early_termination) || ...
        ~logical(cfg.lls.exact_tbs_required)
    error("sixgr:ran1ai1032:InvalidCodingPolicy", ...
        "Exact TBS and LDPC max-50 early-termination policy are mandatory.");
end

if double(cfg.harq.processes) ~= 16 || ...
        double(cfg.harq.maximum_total_transmissions) ~= 4 || ...
        ~isequal(double(cfg.harq.rv_sequence(:)).', [0 2 3 1])
    error("sixgr:ran1ai1032:InvalidHARQPolicy", ...
        "Adaptive runs require 16 HARQ processes, four transmissions, and RV [0 2 3 1].");
end

if ~logical(cfg.link_adaptation.reset_state_per_snr_point) || ...
        ~logical(cfg.link_adaptation.log_entry_identity) || ...
        ~logical(cfg.lls.constant_total_ue_power_across_ranks)
    error("sixgr:ran1ai1032:AdaptationOrPowerContract", ...
        "Independent OLLA state, explicit entry identity, and constant total UE power are mandatory.");
end

if ~logical(cfg.rf.mpr_applied_as_transmit_power_cap) || ...
        logical(cfg.rf.allow_mpr_as_sinr_subtraction) || ...
        ~logical(cfg.rf.prevent_evm_phase_noise_double_count)
    error("sixgr:ran1ai1032:InvalidRFPolicy", ...
        "MPR must be a TX-power cap and EVM/phase noise must not be double counted.");
end

if ~all(logical([cfg.representations.option_a_enabled, ...
        cfg.representations.option_b_enabled, ...
        cfg.representations.option_c_enabled, ...
        cfg.representations.option_d_enabled, ...
        cfg.representations.option_e_enabled]))
    error("sixgr:ran1ai1032:IncompleteRepresentationMatrix", ...
        "Options A-E must all be enabled in the study contract.");
end

sib1 = cfg.sls.initial_access.sib1.pdsch;
sib1Fields = ["prb_start","num_prb","symbol_start","num_symbols","mcs","rv"];
if double(cfg.sls.independent_paired_drops) < 30 || ...
        ~logical(cfg.sls.freeze_packet_arrivals_across_comparators) || ...
        ~logical(cfg.sls.bootstrap_over_independent_drops) || ...
        double(cfg.sls.initial_access.type0.monitoring_occasion_ordinal) < 1 || ...
        double(cfg.sls.initial_access.type0.monitoring_occasion_ordinal) ~= ...
        fix(double(cfg.sls.initial_access.type0.monitoring_occasion_ordinal)) || ...
        ~(isstruct(sib1) && isscalar(sib1) && all(isfield(sib1, sib1Fields)))
    error("sixgr:ran1ai1032:InvalidSLSStatistics", ...
        "SLS requires at least 30 paired drops, frozen arrivals, drop-level bootstrap, and an explicit Type-0 monitoring occasion.");
end
adaptiveSelection = cfg.sls.adaptive_selection;
localValidateSLSArchitecture(cfg.sls);
assert(isfield(cfg.study,'prohibit_uncalibrated_primary_results') && ...
    isequal(cfg.study.prohibit_uncalibrated_primary_results,true), ...
    'sixgr:ran1ai1032:SLSArchitecture', ...
    'study.prohibit_uncalibrated_primary_results must remain true for calibrated SLS estimates.');
if ~logical(adaptiveSelection.calibration_required) || ...
        string(adaptiveSelection.calibration_source) ~= ...
        "measured_fixed_mcs_lls_first_transmission_bler" || ...
        double(adaptiveSelection.target_first_transmission_bler) ~= 0.1 || ...
        ~isequal(double(adaptiveSelection.required_calibration_ranks(:)), [1;2;4]) || ...
        string(adaptiveSelection.uncalibrated_policy) ~= "reject_sls_execution"
    error("sixgr:ran1ai1032:InvalidAdaptiveSLSCalibrationPolicy", ...
        "Adaptive SLS must reject uncalibrated H-entry thresholds and use measured LLS first-TX BLER calibration.");
end
requiredComparators = ["S0";"S1";"S2";"S3";"S4";"S5"];
if double(cfg.sls.sites) ~= 7 || double(cfg.sls.sectors_per_site) ~= 3 || ...
        double(cfg.sls.cells) ~= 21 || ~logical(cfg.sls.wrap_around)
    error("sixgr:ran1ai1032:InvalidSLSGeometry", ...
        "AI 10.3.2 SLS requires 7 sites, 3 sectors/site, 21 cells and wrap-around.");
end
if ~(isscalar(cfg.sls.ues_per_cell) && ...
        double(cfg.sls.ues_per_cell) >= 1 && ...
        double(cfg.sls.ues_per_cell) == fix(double(cfg.sls.ues_per_cell))) || ...
        string(cfg.sls.ue_count_assumption_source) ~= ...
        "6GR_explicit_study_assumption_not_normative_3gpp_requirement"
    error("sixgr:ran1ai1032:InvalidSLSUECountAssumption", ...
        "SLS requires an explicit positive UE-per-cell assumption labelled non-normative.");
end
if ~isfield(cfg.sls, "deployments") || numel(cfg.sls.deployments) ~= 2 || ...
        ~isequal(sort(string({cfg.sls.deployments.id}).'), ...
        sort(["UMa";"UMi-Street-Canyon"])) || ...
        any(~isfinite(double([cfg.sls.deployments.inter_site_distance_m]))) || ...
        any(double([cfg.sls.deployments.inter_site_distance_m]) <= 0)
    error("sixgr:ran1ai1032:InvalidSLSGeometry", ...
        "UMa and UMi-Street-Canyon require explicit positive inter-site distances.");
end
for deploymentIndex = 1:numel(cfg.sls.deployments)
    deployment = cfg.sls.deployments(deploymentIndex);
    topology = sixgr.studies.ran1ai1032.buildHexWraparoundTopology( ...
        cfg.sls.sites, cfg.sls.sectors_per_site, ...
        deployment.inter_site_distance_m);
    sixgr.studies.ran1ai1032.validateSLSHexTopology(topology);
end
if ~isfield(cfg.sls, "fwa_populations") || ...
        ~isequal(sort(string(cfg.sls.fwa_populations(:))), ...
        sort(["Profile-1";"Profile-3"])) || ...
        ~isfield(cfg.sls, "pairing") || ...
        ~isfield(cfg.sls.pairing, "base_seed") || ...
        ~isfield(cfg.sls, "comparators") || ...
        ~isequal(sort(string({cfg.sls.comparators.id}).'), sort(requiredComparators))
    error("sixgr:ran1ai1032:InvalidSLSPairingContract", ...
        "SLS requires Profile-1/Profile-3, an explicit base seed and comparators S0--S5.");
end
localValidateSLSCaseAxes(cfg.sls);
populationDefinitions = cfg.sls.fwa_population_definitions;
populationIDs = string({populationDefinitions.id}).';
if ~isequal(sort(populationIDs), sort(["Profile-1";"Profile-3"]))
    error("sixgr:ran1ai1032:InvalidFWAPopulationDefinitions", ...
        "Exactly one configured definition is required for Profile-1 and Profile-3.");
end

for i = 1:numel(populationDefinitions)
    p = populationDefinitions(i);
    if double(p.indoor_fraction) < 0 || double(p.indoor_fraction) > 1 || ...
            double(p.indoor_low_loss_fraction) ~= 0.5 || ...
            double(p.rooftop_floor_min) ~= 4 || double(p.rooftop_floor_max) ~= 8
        error("sixgr:ran1ai1032:InvalidFWAPopulationDefinitions", ...
            "FWA profiles require a 50/50 indoor O2I mix and rooftop floors 4--8.");
    end
end
profile1 = populationDefinitions(populationIDs == "Profile-1");
profile3 = populationDefinitions(populationIDs == "Profile-3");
if double(profile1.indoor_fraction) ~= 0.8 || ...
        double(profile3.indoor_fraction) ~= 0
    error("sixgr:ran1ai1032:InvalidFWAPopulationDefinitions", ...
        "Profile-1 must be 80%% indoor/20%% rooftop; Profile-3 must be 100%% rooftop.");
end

if ~logical(cfg.outputs.save_csv) || ~logical(cfg.outputs.save_png) || ...
        double(cfg.outputs.png_dpi) < 300 || ...
        ~logical(cfg.outputs.require_plot_csv_identity)
    error("sixgr:ran1ai1032:InvalidOutputContract", ...
        "CSV plus 300-dpi PNG and exact plot-data identity are mandatory.");
end

% Execute the deterministic representation checks as part of validation.
optionA = sixgr.studies.ran1ai1032.MCSCatalog.optionA();
if height(optionA) ~= 32 || optionA.entry_id(28) ~= "B27" || ...
        ~isequal(optionA.entry_id(29:32), ["H0";"H1";"H2";"H3"])
    error("sixgr:ran1ai1032:OptionAMappingMismatch", ...
        "Option A must retain B00-B27 and bind H0-H3 to indices 28-31.");
end
end

function localEqual(value, expected, name)
if ~(isscalar(value) && isfinite(double(value)) && double(value) == expected)
    error("sixgr:ran1ai1032:FixedStudyParameterMismatch", ...
        "%s must equal %.15g.", name, expected);
end
end

function localValidateSLSArchitecture(sls)
required=["architecture","result_classification","effective_sinr_method", ...
    "calibration_policy","missing_calibration_policy","out_of_range_policy", ...
    "harq_policy","spatial_sinr_policy","waveform_calibration_required", ...
    "allow_uncalibrated_beta","allow_truth_export","resource_reservation_policy_path"];
assert(isfield(sls,'execution') && isstruct(sls.execution) && ...
    isscalar(sls.execution) && all(isfield(sls.execution,required)), ...
    'sixgr:ran1ai1032:SLSArchitecture','sls.execution must declare the calibrated SLS architecture and evidence policy.');
e=sls.execution;
assert(strlength(strtrim(string(e.resource_reservation_policy_path)))>0, ...
    'sixgr:ran1ai1032:ResourceReservationPolicy','Configure an explicit resource reservation policy file.');
assert(string(e.architecture)=="calibrated_link_abstraction" && ...
    string(e.result_classification)=="calibrated_sls_estimate_not_waveform_truth" && ...
    string(e.effective_sinr_method)=="calibrated_eesm" && ...
    string(e.calibration_policy)=="exact_profile_allocation_rank_rf_match" && ...
    string(e.missing_calibration_policy)=="reject" && ...
    string(e.out_of_range_policy)=="reject" && ...
    string(e.harq_policy)=="measured_conditional_retransmission_calibration" && ...
    string(e.spatial_sinr_policy)=="per_resource_lmmse_with_explicit_interference_covariance" && ...
    isequal(e.waveform_calibration_required,true) && ...
    isequal(e.allow_uncalibrated_beta,false) && isequal(e.allow_truth_export,false), ...
    'sixgr:ran1ai1032:SLSArchitecture', ...
    'SLS estimates require waveform calibration, explicit interference, calibrated HARQ and no truth relabeling or guessed beta.');
end

function localValidateExecution(cfg)
if ~isfield(cfg.lls,'execution')
    error('sixgr:ran1ai1032:MissingExecutionPolicy','lls.execution must explicitly configure physical F1 execution.');
end
e=cfg.lls.execution;
required=["base_config_path","grid_prbs","cell_id","rnti","tpmi", ...
    "dmrs_type_a_position","dmrs_additional_position","dmrs_cdm_groups_without_data", ...
    "rf_branch","research_transport_policy_path","awgn_spatial_policy", ...
    "awgn_reference_re_energy","tx_power_normalization", ...
    "normalized_total_ue_grid_re_energy","transport_blocks_per_invocation", ...
    "channel_profiles","entry_ids","ranks"];
if ~all(isfield(e,required))
    error('sixgr:ran1ai1032:MissingExecutionPolicy','lls.execution is missing required physical or checkpoint policy fields.');
end
localEqual(e.grid_prbs,273,'lls.execution.grid_prbs');
localEqual(e.dmrs_type_a_position,2,'lls.execution.dmrs_type_a_position');
localEqual(e.dmrs_additional_position,1,'lls.execution.dmrs_additional_position');
localEqual(e.dmrs_cdm_groups_without_data,2,'lls.execution.dmrs_cdm_groups_without_data');
if string(e.base_config_path)~="sixgr.config.defaultConfig" || ...
        string(e.awgn_spatial_policy)~="unit_column_dft" || ...
        string(e.tx_power_normalization)~="constant_total_configured_grid_re_energy" || ...
        strlength(string(e.research_transport_policy_path))==0
    error('sixgr:ran1ai1032:UnsupportedExecutionPolicy', ...
        'Current F1 executor requires the explicit core factory and unit-column DFT AWGN channel.');
end
if string(e.rf_branch)~="ideal_debug"
    for entryID=string(e.entry_ids(:)).'
        modulation="1024QAM";
        if entryID=="B27", modulation="256QAM"; end
        sixgr.studies.ran1ai1032.resolveF1RFBranch(cfg,modulation);
    end
end
validateattributes(e.transport_blocks_per_invocation,{'numeric'},{'scalar','positive','integer','finite'});
if isfield(cfg.harq,'calibration')
    p=cfg.harq.calibration;
    fields=["channel_evolution","feedback_assumption","snr_histories_db", ...
        "fit_episodes_per_history","validation_episodes_per_history","episodes_per_invocation","seed_base"];
    assert(all(isfield(p,fields)) && ...
        string(p.channel_evolution)=="independent_attempt_realizations" && ...
        string(p.feedback_assumption)=="ideal_error_free_delayed_control", ...
        'sixgr:ran1ai1032:HARQCalibrationPolicy','Require explicit physical HARQ collection policy.');
    h=p.snr_histories_db; if iscell(h), h=vertcat(h{:}); end
    if isvector(h), h=reshape(h,1,[]); end
    assert(isnumeric(h) && ismatrix(h) && ~isempty(h) && ...
        size(h,2)==numel(cfg.harq.rv_sequence) && all(isfinite(h),'all') && ...
        size(unique(h,'rows'),1)==size(h,1), ...
        'sixgr:ran1ai1032:HARQCalibrationHistory','Specify unique finite SNR rows with one column per RV.');
    for f=["fit_episodes_per_history","validation_episodes_per_history","episodes_per_invocation","seed_base"]
        validateattributes(p.(f),{'numeric'},{'scalar','integer','positive','finite'});
    end
end
validateattributes(e.awgn_reference_re_energy,{'numeric'},{'scalar','positive','finite'});
validateattributes(e.normalized_total_ue_grid_re_energy,{'numeric'},{'scalar','positive','finite'});
validateattributes(e.cell_id,{'numeric'},{'scalar','integer','>=',0,'<=',1007});
validateattributes(e.rnti,{'numeric'},{'scalar','integer','>=',1,'<=',65535});
validateattributes(e.tpmi,{'numeric'},{'scalar','nonnegative','integer','finite'});
if isempty(e.channel_profiles) || ...
        ~all(ismember(string(e.channel_profiles),["AWGN","CDL-A","CDL-B","CDL-C"])) || ...
        isempty(e.entry_ids) || ~all(ismember(string(e.entry_ids),["B27","H0","H1","H2","H3"])) || ...
        isempty(e.ranks) || ~all(ismember(double(e.ranks),[1 2 3 4]))
    error('sixgr:ran1ai1032:InvalidExecutionSelection','F1 selection contains unsupported profiles, entry identities or ranks.');
end
end

function localValidateSLSCaseAxes(sls)
required = ["ue_tx_chain_cases","ue_power_cases","spatial_modes","rank_policy"];
if ~all(isfield(sls, required))
    error("sixgr:ran1ai1032:MissingSLSCaseAxis", ...
        "SLS UE-chain, UE-power, spatial-mode and adaptive-rank axes must be explicit in study.yaml.");
end

txCases = sls.ue_tx_chain_cases;
powerCases = sls.ue_power_cases;
spatialModes = sls.spatial_modes;
if ~isequal(sort(string({txCases.id}).'), sort(["ue_2tx";"ue_4tx"])) || ...
        ~isequal(sort(double([txCases.tx_chains])).', [2;4])
    error("sixgr:ran1ai1032:InvalidUETxChainCases", ...
        "The SLS campaign requires explicit two-chain and four-chain UE cases.");
end
if ~isequal(sort(string({powerCases.id}).'), ...
        sort(["main_31dbm";"sensitivity_35dbm"])) || ...
        ~isequal(sort(double([powerCases.tx_power_dbm])).', [31;35]) || ...
        ~isequal(sort(string({powerCases.role}).'), sort(["main";"sensitivity"]))
    error("sixgr:ran1ai1032:InvalidUEPowerCases", ...
        "The SLS campaign requires a 31 dBm main case and a 35 dBm sensitivity case.");
end
if ~isequal(sort(string({spatialModes.id}).'), ...
        sort(["mu_mimo_main";"su_mimo_ablation"])) || ...
        nnz(logical([spatialModes.mu_mimo_enabled])) ~= 1 || ...
        nnz(logical([spatialModes.ul_mu_mimo_enabled])) ~= 1
    error("sixgr:ran1ai1032:InvalidSpatialModes", ...
        "The SLS campaign requires one MU-MIMO main case and one SU-MIMO-only ablation.");
end
rankPolicy = sls.rank_policy;
if lower(string(rankPolicy.mode)) ~= "adaptive" || ...
        double(rankPolicy.initial_rank) ~= 1 || ...
        ~logical(rankPolicy.physical_port_cap_required) || ...
        ~logical(rankPolicy.constant_total_ue_power_across_ranks)
    error("sixgr:ran1ai1032:InvalidSLSRankPolicy", ...
        "SLS rank must start at one, adapt causally, respect physical ports and preserve total UE power.");
end

comparators = sls.comparators;
ids = string({comparators.id});
s4 = comparators(ids == "S4");
s5 = comparators(ids == "S5");
if double(s4.max_rank) ~= 2 || double(s5.max_rank) ~= 4
    error("sixgr:ran1ai1032:InvalidSLSRankComparators", ...
        "Comparator S4 must declare max rank 2 and S5 must declare max rank 4.");
end
end
