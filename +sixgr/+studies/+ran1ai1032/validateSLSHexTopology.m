function evidence = validateSLSHexTopology(topology)
%VALIDATESLSHEXTOPOLOGY Fail closed on malformed finite-cluster geometry.

required = ["NumSites","SectorsPerSite","NumCells", ...
    "InterSiteDistance_m","SiteTable","CellTable","TranslationVectors_m"];
if ~isstruct(topology) || ~isscalar(topology) || ...
        ~all(isfield(topology, required))
    error("sixgr:ran1ai1032:MalformedHexTopology", ...
        "Topology is missing required finite-cluster geometry fields.");
end

nSites = double(topology.NumSites);
nSectors = double(topology.SectorsPerSite);
nCells = double(topology.NumCells);
isd = double(topology.InterSiteDistance_m);
siteTable = topology.SiteTable;
cellTable = topology.CellTable;
basis = double(topology.TranslationVectors_m);

localRequire(height(siteTable) == nSites, "site_count", ...
    "Site table cardinality differs from NumSites.");
localRequire(height(cellTable) == nCells && nCells == nSites*nSectors, ...
    "cell_count", "Cell table must contain NumSites*SectorsPerSite rows.");
localRequire(numel(unique(cellTable.CellID)) == nCells, "cell_identity", ...
    "Cell identifiers must be unique.");
localRequire(all(accumarray(cellTable.SiteID, 1, [nSites 1]) == nSectors), ...
    "sector_count", "Every site must contain the configured sector count.");

siteXY = [siteTable.SiteX_m siteTable.SiteY_m];
originRows = hypot(siteXY(:,1), siteXY(:,2)) < 1e-10*isd;
localRequire(nnz(originRows) == 1, "single_origin", ...
    "A centered finite hex cluster requires exactly one origin site.");
if nSites == 7
    ringRadius = hypot(siteXY(~originRows,1), siteXY(~originRows,2));
    localRequire(all(abs(ringRadius - isd) <= 1e-10*isd), ...
        "seven_site_ring_radius", ...
        "The six outer sites of a seven-site cluster must be one ISD from the origin.");
end

basisNorm = vecnorm(basis, 2, 2);
expectedBasisNorm = sqrt(nSites) * isd;
localRequire(all(abs(basisNorm - expectedBasisNorm) <= 1e-10*isd), ...
    "cluster_translation_length", ...
    "Cluster translations must have length sqrt(NumSites)*ISD.");
cosineAngle = dot(basis(1,:), basis(2,:)) / prod(basisNorm);
localRequire(abs(cosineAngle - 0.5) <= 1e-12, ...
    "cluster_translation_angle", ...
    "Hex-cluster translation vectors must be separated by 60 degrees.");
primitiveArea = (sqrt(3)/2) * isd^2;
localRequire(abs(abs(det(basis)) - nSites*primitiveArea) <= ...
    1e-10*nSites*primitiveArea, "cluster_translation_area", ...
    "Periodic-cluster area must equal NumSites times the primitive site-cell area.");

distance = sixgr.studies.ran1ai1032.hexClusterMinImageDistance( ...
    siteXY, siteXY, basis);
distance(eye(nSites) == 1) = NaN;
localRequire(all(abs(min(distance, [], 2, "omitnan") - isd) <= 1e-10*isd), ...
    "minimum_neighbor_distance", ...
    "Every periodic site must retain an ISD nearest-neighbor distance.");
localRequire(all(distance(~eye(nSites)) > 1e-10*isd), ...
    "no_site_collapse", ...
    "Distinct finite-cluster sites must not collapse to zero wrap-around distance.");

probe = [0.173*isd, -0.219*isd];
reference = sixgr.studies.ran1ai1032.hexClusterMinImageDistance( ...
    probe, siteXY, basis);
translated1 = sixgr.studies.ran1ai1032.hexClusterMinImageDistance( ...
    probe + basis(1,:), siteXY, basis);
translated2 = sixgr.studies.ran1ai1032.hexClusterMinImageDistance( ...
    probe - 2*basis(2,:), siteXY, basis);
localRequire(max(abs(reference-translated1), [], "all") <= 1e-10*isd && ...
    max(abs(reference-translated2), [], "all") <= 1e-10*isd, ...
    "translation_invariance", ...
    "Minimum-image distance must be invariant under cluster translations.");

Check = ["site_count";"cell_count";"sector_count"; ...
    "seven_site_ring_radius";"cluster_translation_length"; ...
    "cluster_translation_angle";"cluster_translation_area"; ...
    "minimum_neighbor_distance";"no_site_collapse"; ...
    "translation_invariance"];
Status = repmat("PASS", numel(Check), 1);
evidence = table(Check, Status);
end

function localRequire(condition, checkName, message)
if ~condition
    error("sixgr:ran1ai1032:HexTopologyConformanceFailed", ...
        "Hex topology check '%s' failed: %s", checkName, message);
end
end
