function [wave,evidence]=applyF1TransmitRF(wave,cfg,sampleRateHz)
%APPLYF1TRANSMITRF Execute TX EVM and physical relative power cap for F1.
% The fixed-SNR reference is set BEFORE this stage. The dBm power controller
% parameters define the attenuation ratio; the normalized waveform does not
% become an absolute radiated-power measurement.
b=cfg.rf.studyBranch;
before=mean(sum(abs(double(wave)).^2,2));
evidence=struct('RFBranch',string(b.id),'ConfiguredTXEVMPercent',double(b.tx_evm_percent), ...
    'MeasuredTXEVMPercent',0,'ConfiguredRequestedPowerdBm',double(b.requested_tx_power_dbm), ...
    'ConfiguredMaximumPowerdBm',double(b.power_class_max_dbm)-double(b.mpr_db), ...
    'ConfiguredAppliedPowerdBm',NaN,'MPRdB',double(b.mpr_db),'PowerCapActive',false, ...
    'MeasuredTransmitPowerRatio',1,'ActualTotalTxPower_dBm',NaN, ...
    'AbsolutePowerStatus',"unavailable_normalized_fixed_reference_experiment");
if string(b.id)=="ideal_debug", return; end
f=struct('Endpoint',"tx",'SampleRateHz',sampleRateHz, ...
    'CarrierFrequencyHz',cfg.phy.fc_Hz,'SCSHz',cfg.phy.carrier.SubcarrierSpacing*1000, ...
    'NormalizedCFO',0,'SampleOffset',0,'EVMPercent',double(b.tx_evm_percent), ...
    'EVMCorrelation',eye(size(wave,2)), ...
    'EVMReferencePowerPerChain',mean(abs(double(wave)).^2,1), ...
    'Seed',mod(double(cfg.run.seed)+17011,2^32),'PhaseNoiseEnabled',false, ...
    'RequestedPowerdBm',double(b.requested_tx_power_dbm), ...
    'PowerClassMaxdBm',double(b.power_class_max_dbm),'MPRdB',double(b.mpr_db));
[physical,actual]=sixgr.studies.ran1ai1032.applyRFStudyBranch(wave,f);
nominalAmplitude=sqrt(10^((f.RequestedPowerdBm-30)/10)/before);
wave=cast(physical/nominalAmplitude,'like',wave);
evidence.MeasuredTXEVMPercent=actual.MeasuredAdditiveEVMPercent;
evidence.ConfiguredAppliedPowerdBm=actual.AppliedPowerdBm;
evidence.PowerCapActive=actual.CapActive;
evidence.MeasuredTransmitPowerRatio=mean(sum(abs(double(wave)).^2,2))/before;
expectedRatio=10^((actual.AppliedPowerdBm-f.RequestedPowerdBm)/10);
assert(abs(evidence.MeasuredTransmitPowerRatio-expectedRatio)<1e-10*expectedRatio, ...
    'sixgr:ran1ai1032:F1RFPowerClosure','Physical waveform attenuation differs from the configured TX power cap.');
end
