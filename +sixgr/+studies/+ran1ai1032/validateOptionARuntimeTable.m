function out = validateOptionARuntimeTable()
%VALIDATEOPTIONARUNTIMETABLE Prove runtime indices preserve Option-A meaning.

expected = sixgr.studies.ran1ai1032.MCSCatalog.optionA();
tableName = "experimental_6gr_ai1032_option_a";
for i = 1:height(expected)
    p = sixgr.link.resolveMCSProfile(tableName, expected.indication_index(i));
    if ~logical(p.Valid) || double(p.Qm) ~= expected.Qm(i) || ...
            abs(double(p.TargetCodeRate) - ...
            expected.target_code_rate_x1024(i) / 1024) > 1e-14
        error("sixgr:ran1ai1032:OptionARuntimeMappingMismatch", ...
            "Runtime index %d does not preserve entry %s.", ...
            expected.indication_index(i), expected.entry_id(i));
    end
end
out = struct("Ok", true, "Table", tableName, "EntryCount", height(expected), ...
    "IndexWidthBits", 5, "StandardNR", false, ...
    "TruthClassification", "6GR_RAN1_study_candidate_not_normative_NR_MCS_table", ...
    "AdaptiveSelectionStatus", ...
    "blocked_until_LLS_calibrated_required_SINR_thresholds_are_installed");
end
