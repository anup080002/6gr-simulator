function row = localRow(item, status, source, symbol, evidence, correctiveChange)
row = struct("Item", string(item), "Status", string(status), ...
    "Source", string(source), "FunctionOrClass", string(symbol), ...
    "Evidence", string(evidence), "CorrectiveChange", string(correctiveChange));
end

function row = localReferenceRow(feature, status, source, use)
row = struct("Feature", string(feature), "Status", string(status), ...
    "ViennaSource", string(source), "SixGRUse", string(use));
end

function localAssertSources(repoRoot, rows)
for i = 1:numel(rows)
    paths = split(rows(i).Source, ";");
    for j = 1:numel(paths)
        rel = strtrim(paths(j));
        if strlength(rel) == 0 || ~contains(rel, "/")
            continue;
        end
        absPath = fullfile(repoRoot, strrep(rel, "/", filesep));
        if exist(absPath, "file") ~= 2 && exist(absPath, "dir") ~= 7
            error("sixgr:studies:ran1ai1032:MissingAuditSource", ...
                "Audit source does not exist: %s", rel);
        end
    end
end
end

