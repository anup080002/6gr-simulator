cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>

fprintf(fid, "# AI 10.3.2 modulation implementation audit\n\n");
fprintf(fid, "Overall mandatory implementation gate: **%s**\n\n", ...
    localToken(overallPass, "PASS", "FAIL"));
fprintf(fid, ["PASS requires focused executable evidence or a deterministic invariant. " + ...
    "PARTIAL means machinery exists but the exact campaign branch is not yet qualified. " + ...
    "No performance result is implied by this audit.\n\n"]);
fprintf(fid, "| Item | Status | Source | Class/function | Evidence | Corrective change |\n");
fprintf(fid, "|---|---|---|---|---|---|\n");
for i = 1:numel(rows)
    fprintf(fid, "| %s | **%s** | `%s` | `%s` | %s | %s |\n", ...
