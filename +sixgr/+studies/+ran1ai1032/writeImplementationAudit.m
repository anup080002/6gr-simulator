    fprintf(fid, "| %s | **%s** | `%s` | %s |\n", ...
        localEscape(vienna(i).Feature), localEscape(vienna(i).Status), ...
        localEscape(vienna(i).ViennaSource), localEscape(vienna(i).SixGRUse));
