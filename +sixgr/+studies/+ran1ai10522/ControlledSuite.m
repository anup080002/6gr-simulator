classdef ControlledSuite
    %CONTROLLEDSUITE Bounded actual PDSCH waveform execution and reductions.

    methods (Static)
        function out = run(cfg, scfg, runFolder)
            internal = sixgr.lls6g.buildInternalConfig(scfg, runFolder);
            snr = double(cfg.study.execution.snr_points_db(:));
            frames = double(cfg.study.execution.transport_blocks_per_point);
            trials = cell(numel(snr),1); pointRows = repmat(localPointRow(),numel(snr),1);
            startTime = tic;
            for k=1:numel(snr)
                rng(double(cfg.study.master_seed)+k-1,"twister");
                pointStart=tic;
                result=sixgr.link.runDLPDSCHThroughput(internal, ...
                    "ExecutionProfile","phy_calibration", ...
                    "NumFrames",frames,"SNR_dB",snr(k));
                T=result.TrialTable;
                if result.Skipped || height(T)~=frames || any(logical(T.Crash))
                    error("sixgr:ran1ai10522:CanonicalWaveformUnavailable", ...
                        "Canonical PDSCH point %.3g dB did not produce %d crash-free rows.", ...
                        snr(k),frames);
                end
                if string(result.ApproximationMode)~="none" || ...
                        any(logical(T.FallbackFlag)) || any(logical(T.PlaceholderFlag))
                    error("sixgr:ran1ai10522:FallbackEvidenceForbidden", ...
                        "Canonical PDSCH point %.3g dB contains fallback/proxy evidence.",snr(k));
                end
                if ~all(string(T.ExecutionBackend)=="legacy_pdsch_calibration_facades") || ...
                        ~all(string(T.ExecutionTaxonomy)=="isolated_phy_calibration")
                    error("sixgr:ran1ai10522:UnexpectedExecutionBackend", ...
                        "PDSCH controlled rows did not retain the declared calibration backend/taxonomy.");
                end
                T=addvars(T,repmat(snr(k),height(T),1), ...
                    repmat("CONTROLLED_LLS",height(T),1), ...
                    repmat("INCOMPLETE",height(T),1),false(height(T),1), ...
                    'Before',1,'NewVariableNames',{'RequestedStudySNR_dB', ...
                    'EvidenceClass','ConvergenceStatus','TDocReady'});
                trials{k}=T;
                crcPass=logical(T.CRCPass); errors=nnz(~crcPass); n=height(T);
                [lo,hi]=sixgr.studies.ran1ai10522.wilsonInterval( ...
                    errors,n,double(cfg.study.execution.confidence_level));
                pointRows(k)=struct("SNR_dB",snr(k),"TransmittedTBs",n, ...
                    "BlockErrors",errors,"BLER",errors/n,"BLER_CI_Low",lo, ...
                    "BLER_CI_High",hi,"BitErrors",sum(double(T.BitErrors)), ...
                    "BitsCompared",sum(double(T.BitsCompared)), ...
                    "BER",sum(double(T.BitErrors))/max(sum(double(T.BitsCompared)),1), ...
                    "Goodput_Mbps",mean(double(T.Goodput_Mbps),"omitnan"), ...
                    "CENMSE_dB",mean(double(T.NMSE_dB),"omitnan"), ...
                    "PostEqSINR_dB",mean(double(T.PostEqSINR_dB),"omitnan"), ...
                    "Runtime_s",toc(pointStart),"ExecutionBackend",string(result.ExecutionBackend), ...
                    "ChannelModel",string(T.ChannelModel(1)),"ApproximationMode","none", ...
                    "EvidenceClass","CONTROLLED_LLS","ConvergenceStatus","INCOMPLETE", ...
                    "CalibrationStatus","not_common_evm_calibrated","TDocReady",false, ...
                    "Status","PASS","StopReason","bounded_short_run_below_statistical_minimum");
            end
            out=struct(); out.Trials=vertcat(trials{:});
            out.Points=struct2table(pointRows,"AsArray",true);
            out.BLER=out.Points(:,["SNR_dB","TransmittedTBs","BlockErrors","BLER", ...
                "BLER_CI_Low","BLER_CI_High","EvidenceClass","ConvergenceStatus", ...
                "CalibrationStatus","TDocReady","Status","StopReason"]);
            out.Goodput=out.Points(:,["SNR_dB","Goodput_Mbps","TransmittedTBs", ...
                "EvidenceClass","ConvergenceStatus","TDocReady","Status"]);
            out.CENMSE=out.Points(:,["SNR_dB","CENMSE_dB","TransmittedTBs", ...
                "EvidenceClass","ConvergenceStatus","TDocReady","Status"]);
            out.PostEqSINR=out.Points(:,["SNR_dB","PostEqSINR_dB","TransmittedTBs", ...
                "EvidenceClass","ConvergenceStatus","TDocReady","Status"]);
            out.Runtime=out.Points(:,["SNR_dB","Runtime_s","TransmittedTBs", ...
                "ExecutionBackend","ChannelModel","ApproximationMode","EvidenceClass","Status"]);
            out.TotalRuntime_s=toc(startTime);
        end
    end
end

function row=localPointRow()
row=struct("SNR_dB",NaN,"TransmittedTBs",0,"BlockErrors",0,"BLER",NaN, ...
    "BLER_CI_Low",NaN,"BLER_CI_High",NaN,"BitErrors",0,"BitsCompared",0, ...
    "BER",NaN,"Goodput_Mbps",NaN,"CENMSE_dB",NaN,"PostEqSINR_dB",NaN, ...
    "Runtime_s",NaN,"ExecutionBackend","","ChannelModel","", ...
    "ApproximationMode","none","EvidenceClass","CONTROLLED_LLS", ...
    "ConvergenceStatus","INCOMPLETE","CalibrationStatus", ...
    "not_common_evm_calibrated","TDocReady",false,"Status","PASS", ...
    "StopReason","bounded_short_run_below_statistical_minimum");
end
