classdef ArtifactAuditor
    %ARTIFACTAUDITOR Rectangular CSV, raster, hash, and publication gates.
    methods (Static)
        function [audit,frameAudit,passed,publicationPassed]=run(runFolder)
            requiredCsv=[ ...
                "manifests/scenario_matrix.csv";"manifests/scenario_manifest.csv"; ...
                "manifests/resolved_config_manifest.csv";"manifests/environment_manifest.csv"; ...
                "manifests/proposal_evidence_matrix.csv";"manifests/point_status.csv"; ...
                "manifests/limitations.csv";"manifests/artifact_manifest.csv"; ...
                "manifests/figure_manifest.csv";"manifests/frame_image_audit.csv"; ...
                "csv/deterministic/dmrs_time_profile.csv";"csv/deterministic/dmrs_group_positions.csv"; ...
                "csv/deterministic/dmrs_re_accounting.csv";"csv/deterministic/td_occ_despreading_audit.csv"; ...
                "csv/deterministic/nested_family.csv";"csv/deterministic/nested_receiver_classification.csv"; ...
                "csv/deterministic/covariance_metrics.csv";"csv/deterministic/fd_pattern_manifest.csv"; ...
                "csv/deterministic/fd_occ_cdm_validity.csv";"csv/deterministic/dmrs_sequence_metrics.csv"; ...
                "csv/deterministic/port_count_metrics.csv";"csv/deterministic/bundle_map.csv"; ...
                "csv/deterministic/rbg_bundle_compatibility.csv";"csv/deterministic/interleaver_map.csv"; ...
                "csv/deterministic/ptrs_phase_metrics.csv";"csv/deterministic/tb_mapping_metrics.csv"; ...
                "csv/deterministic/mcs_segmentation_metrics.csv";"csv/deterministic/cw_layer_mapping_metrics.csv"; ...
                "csv/deterministic/multitrp_profile_audit.csv";"csv/deterministic/mrss_validity_metrics.csv"; ...
                "csv/controlled/bler_points.csv";"csv/controlled/goodput_points.csv"; ...
                "csv/controlled/ce_nmse_points.csv";"csv/controlled/posteq_sinr_points.csv"; ...
                "csv/controlled/runtime_metrics.csv"];
            rows=repmat(struct("Artifact","","Check","","Pass",false,"Details",""),0,1);
            for rel=requiredCsv.'
                path=fullfile(runFolder,replace(rel,"/",filesep)); exists=exist(path,"file")==2;
                rectangular=false; details="missing";
                if exists
                    try
                        T=readtable(path,"Delimiter",",","VariableNamingRule","preserve");
                        rectangular=height(T)>0 && width(T)>0; details=sprintf("rows=%d,cols=%d",height(T),width(T));
                    catch ME, details="read_failed:"+string(ME.identifier); end
                end
                rows(end+1,1)=struct("Artifact",rel,"Check","csv_exists_rectangular_nonempty", ... %#ok<AGROW>
                    "Pass",exists&&rectangular,"Details",details);
            end
            manifestPath=fullfile(runFolder,"manifests","figure_manifest.csv");
            frameRows=repmat(struct("FigureId","","PNGPath","","DecodeOk",false, ...
                "HashMatch",false,"WidthPx",0,"HeightPx",0,"NonBlank",false,"Status","FAIL"),0,1);
            if exist(manifestPath,"file")==2
                F=readtable(manifestPath,"Delimiter",",","VariableNamingRule","preserve");
                for k=1:height(F)
                    path=fullfile(runFolder,replace(string(F.PNGPath(k)),"/",filesep));
                    decode=false; hash=false; w=0; h=0; nonblank=false;
                    try
                        info=imfinfo(path); pix=double(imread(path)); decode=true; w=info.Width; h=info.Height;
                        nonblank=std(pix,0,"all")>0; hash=sixgr.csi.studyFileSHA256(path)==string(F.PNGSHA256(k));
                    catch, end
                    pass=decode&&hash&&nonblank&&w>=800&&h>=450;
                    frameRows(end+1,1)=struct("FigureId",string(F.FigureId(k)), ... %#ok<AGROW>
                        "PNGPath",string(F.PNGPath(k)),"DecodeOk",decode,"HashMatch",hash, ...
                        "WidthPx",w,"HeightPx",h,"NonBlank",nonblank,"Status",localStatus(pass));
                end
            end
            frameAudit=struct2table(frameRows,"AsArray",true);
            imagePass=height(frameAudit)>=14 && all(frameAudit.Status=="PASS");
            rows(end+1,1)=struct("Artifact","manifests/figure_manifest.csv", ...
                "Check","all_png_decode_hash_dimensions_nonblank","Pass",imagePass, ...
                "Details",sprintf("figures=%d",height(frameAudit)));
            noVector=isempty(dir(fullfile(runFolder,"**","*.svg"))) && isempty(dir(fullfile(runFolder,"**","*.pdf")));
            rows(end+1,1)=struct("Artifact","figures","Check","raster_only_no_svg_pdf", ...
                "Pass",noVector,"Details","user raster-only contract");
            noReady=~isfolder(fullfile(runFolder,"tdoc_ready"));
            rows(end+1,1)=struct("Artifact","tdoc_ready","Check","incomplete_run_not_promoted", ...
                "Pass",noReady,"Details","bounded campaign is not publication qualified");
            artifactPath=fullfile(runFolder,"manifests","artifact_manifest.csv");
            manifestHashPass=false; hashRows=0;
            if exist(artifactPath,"file")==2
                M=readtable(artifactPath,"Delimiter",",","VariableNamingRule","preserve");
                manifestHashPass=height(M)>0;
                for k=1:height(M)
                    path=fullfile(runFolder,replace(string(M.RelativePath(k)),"/",filesep));
                    ok=exist(path,"file")==2 && sixgr.csi.studyFileSHA256(path)==string(M.SHA256(k));
                    manifestHashPass=manifestHashPass&&ok; hashRows=hashRows+1;
                end
            end
            rows(end+1,1)=struct("Artifact","manifests/artifact_manifest.csv", ...
                "Check","artifact_manifest_hash_binding","Pass",manifestHashPass, ...
                "Details",sprintf("bound_artifacts=%d",hashRows));
            audit=struct2table(rows,"AsArray",true); passed=all(audit.Pass);
            proposal=readtable(fullfile(runFolder,"manifests","proposal_evidence_matrix.csv"),"Delimiter",",","VariableNamingRule","preserve");
            points=readtable(fullfile(runFolder,"manifests","point_status.csv"),"Delimiter",",","VariableNamingRule","preserve");
            publicationPassed=passed&&all(logical(proposal.ClaimSupported))&&all(string(points.Status)=="PASS")&& ...
                all(points.TDocReady);
        end
    end
end
function value=localStatus(tf),if tf,value="PASS";else,value="FAIL";end,end
