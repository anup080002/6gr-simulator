classdef ScenarioRegistry
    %SCENARIOREGISTRY Evidence-class ownership for every requested group.

    methods (Static)
        function T=table(cfg,mode)
            ids=["A";"B";"C";"D";"E";"F";"G";"H";"I";"J"];
            names=["CSI computation-state association and CPU lifecycle"; ...
                "Reference-state-associated DMRS CSI refinement"; ...
                "Interference-hypothesis age";"Early/fast CSI"; ...
                "Bounded event-triggered CSI"; ...
                "Differential multi-hypothesis CSI"; ...
                "128/256/512-port CSI-RS";"CSI-RS sharing and sequence identity"; ...
                "Walsh versus DFT OCC and CDM";"Multi-slot/multi-RB CSI-RS"];
            evidence=["PROCEDURE";"LLS_CONTROLLED";"SANITY|LLS_CONTROLLED"; ...
                "PROCEDURE|LLS_CONTROLLED";"SANITY|PROCEDURE|LLS_CONTROLLED"; ...
                "ANALYTICAL|LLS_CONTROLLED";"ANALYTICAL|LLS_CONTROLLED"; ...
                "ANALYTICAL|LLS_CONTROLLED";"ANALYTICAL|LLS_CONTROLLED"; ...
                "ANALYTICAL|LLS_CONTROLLED"];
            status=repmat("PLANNED",10,1);
            if any(lower(string(mode))==["smoke","bounded_qualification","controlled"])
                status(:)="EXECUTE";
            end
            tdocUsable=false(10,1);
            limitation=repmat("Controlled/screening evidence; quantitative TDoc claim gate remains closed.",10,1);
            limitation(1)="Procedure evidence only; not waveform LLS.";
            limitation(3)="Sanity and controlled single-link evidence; no network UPT claim.";
            limitation(4)="Procedure linked to controlled PDSCH evidence; no SLS UPT.";
            limitation(5)="Single-UE event burstiness only; simultaneous multi-UE load is NOT_EVALUATED.";
            limitation(6)="Physical gNB transmit energy only; network and UE energy saving are NOT_EVALUATED.";
            commonVerified=logical(cfg.identity.common_evm_verified);
            if commonVerified, tdocUsable(2:end)=true; end
            T=table(ids,names,evidence,status,repmat(commonVerified,10,1), ...
                tdocUsable,limitation,'VariableNames',{'ScenarioGroup','Name', ...
                'EvidenceClasses','ExecutionStatus','CommonEVMVerified', ...
                'QuantitativeTDocEligible','Limitation'});
        end
    end
end
