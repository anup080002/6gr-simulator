function result=runTDocSuite(mode,options)
%RUNTDOCSUITE RAN1 10.5.3.1 DL-CSI suite entry point.
arguments
    mode (1,1) string {mustBeMember(mode,["plan","unit","smoke","bounded","bounded_qualification", ...
        "controlled","common_evm","figure_replay","audit"])} = "bounded_qualification"
    options.ConfigPath (1,1) string = "simulator/configs/csi_tdoc/bounded_qualification.yaml"
    options.OutputRoot (1,1) string = "results/csi_tdoc"
    options.RunId (1,1) string = ""
    options.RunFolder (1,1) string = ""
end
repo=localRepoRoot();
effectiveMode=mode;
if mode=="bounded", effectiveMode="bounded_qualification"; end
if any(mode==["figure_replay","audit"])
    if options.RunFolder==""
        error("sixgr:csi:RunFolderRequired","RunFolder is required for %s.",mode);
    end
    runFolder=string(options.RunFolder);
    [cfg,prov]=sixgr.csi.loadTDocConfig(fullfile(runFolder,"manifests","resolved_config.yaml"));
    context=localContext(cfg,prov,runFolder);
    if mode=="figure_replay"
        result=sixgr.csi.FigureManifest.replay(runFolder,cfg,context);
    else
        registry=sixgr.csi.ScenarioRegistry.table(cfg,"bounded_qualification");
        sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests", ...
            "proposal_evidence_matrix.csv"),localProposal(registry),context);
        sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests", ...
            "limitations.csv"),localLimitations(cfg),context);
        [frameAudit,framePassed]=sixgr.csi.frameImageAudit(runFolder);
        sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests", ...
            "frame_image_audit.csv"),frameAudit,context);
        [result,passed]=sixgr.csi.auditTDocRun(runFolder);
        passed=passed&&framePassed;
        sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests","artifact_audit.csv"),result,context);
    if ~passed, error("sixgr:csi:ArtifactGateFailed","CSI artifact audit failed."); end
        auditReplay=struct("SchemaVersion","sixgr.csi.tdoc.audit/v1", ...
            "RunId",char(context.RunId),"AuditChecks",height(result), ...
            "AuditPassed",logical(passed),"AuditedUTC", ...
            char(datetime("now","TimeZone","UTC")));
        sixgr.util.jsonWrite(fullfile(runFolder,"manifests", ...
            "audit_replay_manifest.json"),auditReplay);
        highPort=readtable(fullfile(runFolder,"csv","lls", ...
            "port_count_lls_points.csv"),"VariableNamingRule","preserve");
        pdsch=readtable(fullfile(runFolder,"csv","lls", ...
            "pdsch_anchor_trials.csv"),"VariableNamingRule","preserve");
        figures=readtable(fullfile(runFolder,"manifests", ...
            "figure_manifest.csv"),"VariableNamingRule","preserve");
        summary=struct("RunFolder",runFolder, ...
            "CSVCount",numel(dir(fullfile(runFolder,"**","*.csv"))), ...
            "PNGCount",numel(dir(fullfile(runFolder,"**","*.png"))), ...
            "PDFCount",numel(dir(fullfile(runFolder,"**","*.pdf"))), ...
            "FigureCount",height(figures),"AuditChecks",height(result), ...
            "AuditPassed",logical(passed),"HighPortPoints",height(highPort), ...
            "PDSCHTransportBlocks",height(pdsch), ...
            "CommonEVMVerified",logical(cfg.identity.common_evm_verified), ...
            "PublicationQualified",false,"SemanticFigurePassed", ...
            height(figures)==20&&all(string(figures.SemanticAuditStatus)=="PASS"));
        localSummary(runFolder,summary,registry,"audit_replay");
        localManifest(summary,cfg,prov,context,"audit_replay");
    end
    return;
end
[cfg,prov]=sixgr.csi.loadTDocConfig(options.ConfigPath);
if effectiveMode=="common_evm" && ~logical(cfg.identity.common_evm_verified)
    error("sixgr:csi:MissingCommonEVM", ...
        "LLS_COMMON_EVM cannot run: no exact verified common-EVM source/hash is configured.");
end
if effectiveMode=="controlled"
    error("sixgr:csi:ControlledCampaignNotYetQualified", ...
        "The complete controlled sweep is intentionally blocked until the bounded "+ ...
        "artifact gate passes and missing waveform groups in gap_analysis.csv are closed.");
end
if options.RunId==""
    runId="ran1_10_5_3_1_"+effectiveMode+"_"+string(datetime("now","Format","yyyyMMdd_HHmmss"));
else, runId=options.RunId; end
runFolder=string(fullfile(options.OutputRoot,runId));
localLayout(runFolder); context=localContext(cfg,prov,runFolder); context.RunId=runId;
[inventory,gaps]=sixgr.csi.buildRepositoryInventory(repo);
registry=sixgr.csi.ScenarioRegistry.table(cfg,effectiveMode);
flow=sixgr.csi.executionFlowContract(repo);
sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests","repository_inventory.csv"),inventory,context);
sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests","gap_analysis.csv"),gaps,context);
sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests","scenario_registry.csv"),registry,context);
sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests","execution_flow_contract.csv"),flow,context);
sixgr.lls6g.config.writeYAML(fullfile(runFolder,"manifests","resolved_config.yaml"),cfg);
copyfile(prov.ConfigPath,fullfile(runFolder,"manifests","input_config.yaml"));
if effectiveMode=="plan"
    result=struct("RunFolder",runFolder,"Inventory",inventory,"GapAnalysis",gaps, ...
        "ScenarioRegistry",registry,"ExecutionFlow",flow,"Passed",true); localManifest(result,cfg,prov,context,mode);
    return;
elseif effectiveMode=="unit"
    testCSITDocExactModels;
    result=struct("RunFolder",runFolder,"Passed",true); localManifest(result,cfg,prov,context,mode);
    return;
end

analytical=sixgr.csi.runAnalyticalScenarios(cfg);
procedure=sixgr.csi.runProcedureScenarios(cfg);
waveform=sixgr.csi.runBoundedScenario(cfg,prov);
paths=sixgr.csi.writeSuiteTables(runFolder,context,registry,inventory,gaps, ...
    analytical,procedure,waveform);
sixgr.csi.writeFigureSourceTables(runFolder,context,cfg);
figures=sixgr.csi.FigureManifest.replay(runFolder,cfg,context);
[frameAudit,framePassed]=sixgr.csi.frameImageAudit(runFolder);
sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests", ...
    "frame_image_audit.csv"),frameAudit,context);
proposal=localProposal(registry); sixgr.csi.ResultWriter.write( ...
    fullfile(runFolder,"manifests","proposal_evidence_matrix.csv"),proposal,context);
limitations=localLimitations(cfg); sixgr.csi.ResultWriter.write( ...
    fullfile(runFolder,"manifests","limitations.csv"),limitations,context);
coveragePassed=true; coverageChecks=0;
if effectiveMode=="bounded_qualification"
    [coverage,coveragePassed]=localBoundedCoverage(runFolder,registry,waveform,gaps);
    sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests", ...
        "bounded_qualification_coverage.csv"),coverage,context);
    coverageChecks=height(coverage);
end
[audit,auditPassed]=sixgr.csi.auditTDocRun(runFolder);
passed=auditPassed&&framePassed&&coveragePassed;
sixgr.csi.ResultWriter.write(fullfile(runFolder,"manifests","artifact_audit.csv"),audit,context);
summary=struct("RunFolder",runFolder,"CSVCount",numel(dir(fullfile(runFolder,"**","*.csv"))), ...
    "PNGCount",numel(dir(fullfile(runFolder,"**","*.png"))), ...
    "PDFCount",numel(dir(fullfile(runFolder,"**","*.pdf"))), ...
    "FigureCount",height(figures),"AuditChecks",height(audit), ...
    "AuditPassed",passed,"HighPortPoints",height(waveform.HighPort), ...
    "PDSCHTransportBlocks",height(waveform.PDSCHTrials), ...
    "CommonEVMVerified",logical(cfg.identity.common_evm_verified), ...
    "PublicationQualified",false,"SemanticFigurePassed", ...
    height(figures)==20&&all(figures.SemanticAuditStatus=="PASS"));
if effectiveMode=="bounded_qualification"
    summary.BoundedCoverageChecks=coverageChecks;
    summary.BoundedCoveragePassed=coveragePassed;
end
localSummary(runFolder,summary,registry,effectiveMode); localManifest(summary,cfg,prov,context,effectiveMode);
result=struct("RunFolder",runFolder,"Summary",summary,"Audit",audit, ...
    "Figures",figures,"ScenarioRegistry",registry,"Passed",passed);
if ~passed
    error("sixgr:csi:ArtifactGateFailed", ...
        "CSI %s artifact/runtime coverage gate failed.",effectiveMode);
end
fprintf("RAN1 10.5.3.1 CSI %s PASS: %s (%d CSV, %d PNG, %d PDF, %d audit checks)\n", ...
    effectiveMode,runFolder,summary.CSVCount,summary.PNGCount,summary.PDFCount,summary.AuditChecks);
end

function [coverage,passed]=localBoundedCoverage(runFolder,registry,waveform,gaps)
rows=repmat(struct("CheckId","","Requirement","","Observed",0, ...
    "Pass",false,"Status","FAIL"),0,1);
    function add(id,requirement,observed,ok)
        rows(end+1,1)=struct("CheckId",string(id), ...
            "Requirement",string(requirement),"Observed",double(observed), ...
            "Pass",logical(ok),"Status",string("FAIL")); %#ok<AGROW>
        if ok, rows(end).Status="PASS"; end
    end
add("FLOW","Every canonical runtime owner executed", ...
    height(waveform.CanonicalFlow.Trace),all(waveform.CanonicalFlow.Trace.Pass));
add("GROUPS","Every A-J scenario group is registered",height(registry), ...
    all(ismember(["A","B","C","D","E","F","G","H","I","J"], ...
        registry.ScenarioGroup)));
missingCapabilities=nnz(gaps.Status=="MISSING_CAPABILITY");
add("GAPS","No bounded capability is reported as missing", ...
    missingCapabilities,missingCapabilities==0);
highPort=waveform.HighPort;
highPortOk=all(ismember([128 256 512],unique(highPort.TxPorts).')) && ...
    all(highPort.EvidenceClass=="LLS_CONTROLLED") && ...
    all(highPort.ExecutionBackend=="nr_ofdm_streamed_high_port_occ_waveform") && ...
    all(highPort.ApproximationMode=="none") && ...
    all(isfinite(highPort.NMSELinear)) && all(isfinite(highPort.SGCS));
add("HIGH_PORT","128/256/512-port CSI-RS uses calibrated NR OFDM", ...
    height(highPort),highPortOk);
pdsch=waveform.PDSCHTrials;
pdschNames=string(pdsch.Properties.VariableNames);
pdschOk=height(pdsch)>=numel(unique(pdsch.SNRIndex)) && ...
    all(ismember(["TxProcessChain","RxProcessChain","LLRSource", ...
        "CRCSource","FallbackUsed"],pdschNames)) && ...
    all(strlength(string(pdsch.TxProcessChain))>0) && ...
    all(strlength(string(pdsch.RxProcessChain))>0) && ...
    all(string(pdsch.LLRSource)=="nrPDSCHDecode_soft_llr") && ...
    all(string(pdsch.CRCSource)=="decoded_transport_block_crc") && ...
    ~any(pdsch.FallbackUsed);
add("PDSCH","Production PDSCH/DL-SCH Tx-to-Rx rows contain no fallback", ...
    height(pdsch),pdschOk);
uci=waveform.CanonicalFlow.PUCCH;
uciOk=height(uci)==4 && all(uci.BitErrors==0) && ...
    ~any(uci.CRCFailed|uci.ContentMismatch) && ...
    all(uci.ExecutionBackend~="") && all(uci.EvidenceClass=="LLS_CONTROLLED");
add("PUCCH","Four typed CSI roles traverse the production PUCCH waveform", ...
    height(uci),uciOk);
energy=waveform.EnergyHypotheses.Performance;
energyOk=height(energy)==height(waveform.EnergyHypotheses.Reconstruction) && ...
    all(energy.ExecutionBackend== ...
        "sixgr.phy.dl.PDSCH_Tx_hybrid_element_domain_to_PDSCH_Rx") && ...
    all(energy.ApproximationMode=="none") && all(isfinite(energy.PostEqSINRdB));
add("ENERGY","Every energy hypothesis uses measured CSI and production PDSCH", ...
    height(energy),energyOk);
interference=waveform.Interference.Points;
interferenceOk=height(interference)==2 && ...
    numel(unique(interference.CovarianceSHA256))==2 && ...
    all(interference.InterferenceSource== ...
        "independent_transport_block_waveform_and_channel") && ...
    all(interference.CovarianceApplied) && ...
    all(interference.CovarianceIncludesNoise) && ...
    all(interference.NoiseAddedExactlyOnce) && ...
    all(interference.ApproximationMode=="none") && ...
    all(isfinite(interference.PostEqSINRdB));
add("INTERFERENCE","Current and aged measured covariance replay the same PDSCH waveform", ...
    height(interference),interferenceOk);
multi=waveform.MultiSlot;
multiOk=height(multi.Trace)==double(multi.Summary.M1(1)) && ...
    all(multi.Trace.ExecutionBackend=="nr_ofdm_streamed_high_port_occ_waveform") && ...
    all(multi.Trace.ApproximationMode=="none") && ...
    height(multi.Summary)==2 && all(isfinite(multi.Summary.NMSELinear)) && ...
    height(multi.PDSCHPerformance)==2 && ...
    all(multi.PDSCHPerformance.PDSCHApplied) && ...
    all(isfinite(multi.PDSCHPerformance.PostEqSINRdB)) && ...
    all(multi.PDSCHPerformance.ExecutionBackend== ...
        "sixgr.phy.dl.PDSCH_Tx_hybrid_element_domain_to_PDSCH_Rx");
add("MULTISLOT","Every multi-slot CSI point is an NR OFDM waveform measurement", ...
    height(multi.Trace),multiOk);
scopeFiles=dir(fullfile(runFolder,"csv","scope","*.csv"));
add("NO_SCOPE","No bounded primary artifact is scope-only",numel(scopeFiles), ...
    isempty(scopeFiles));
allCsv=dir(fullfile(runFolder,"csv","**","*.csv"));
notEvaluated=0;
for k=1:numel(allCsv)
    T=readtable(fullfile(allCsv(k).folder,allCsv(k).name), ...
        "Delimiter",",","VariableNamingRule","preserve");
    names=string(T.Properties.VariableNames);
    if ismember("EvidenceClass",names)
        notEvaluated=notEvaluated+nnz(string(T.EvidenceClass)=="NOT_EVALUATED");
    end
    if ismember("Status",names)
        notEvaluated=notEvaluated+nnz(contains(string(T.Status),"NOT_EVALUATED"));
    end
end
add("NO_NOT_EVALUATED","No bounded evidence row is unevaluated", ...
    notEvaluated,notEvaluated==0);
coverage=struct2table(rows,"AsArray",true); passed=all(coverage.Pass);
end

function context=localContext(cfg,prov,runFolder)
[s,commit]=system("git rev-parse HEAD"); if s~=0, commit="unknown"; end
context=struct("RunId",string(localLastPath(runFolder)), ...
    "ConfigHash",string(prov.ConfigSHA256),"GitCommit",strtrim(string(commit)), ...
    "Config",cfg);
end
function localLayout(folder)
dirs=["csv/analytical","csv/sanity","csv/procedure","csv/lls","csv/scope","csv/figures", ...
    "figures","manifests","mat","logs"];
for d=dirs
    target=fullfile(folder,d); if ~isfolder(target), mkdir(target); end
end
end
function name=localLastPath(path)
[~,name]=fileparts(char(path)); name=string(name);
end
function root=localRepoRoot()
root=fileparts(fileparts(fileparts(mfilename("fullpath"))));
end
function T=localProposal(registry)
figureIds=["FIG-2.2-1|FIG-2.2-2";"FIG-2.3-1"; ...
    "FIG-2.4-1|FIG-2.4-2";"FIG-2.5-1"; ...
    "FIG-2.6-1|FIG-2.6-2";"FIG-2.7-1"; ...
    "FIG-2.8-1|FIG-2.8-2";"FIG-2.9-1|FIG-2.9-2"; ...
    "FIG-2.10-1|FIG-2.10-2|FIG-2.10-3"; ...
    "FIG-2.11-1|FIG-2.11-2|FIG-2.11-3"];
rows=repmat(struct("ProposalNumber","","TDocSection","10.5.3.1", ...
    "ScenarioIds","","RequiredMetrics","See scenario CSVs", ...
    "FigureIds","", ...
    "EvidenceClass","","ResultStatus","SCREENING_EXECUTED", ...
    "CalibrationStatus","COMMON_EVM_MISSING","ClaimSupported",false, ...
    "Limitation",""),0,1);
q=0;
for k=1:height(registry)
    classes=split(string(registry.EvidenceClasses(k)),"|");
    for c=1:numel(classes)
        q=q+1;
        rows(q,1)=struct("ProposalNumber","P"+k+"-"+c, ...
            "TDocSection","10.5.3.1","ScenarioIds",registry.ScenarioGroup(k), ...
            "RequiredMetrics","See scenario CSVs","FigureIds",figureIds(k), ...
            "EvidenceClass",classes(c), ...
            "ResultStatus","SCREENING_EXECUTED", ...
            "CalibrationStatus","COMMON_EVM_MISSING","ClaimSupported",false, ...
            "Limitation",registry.Limitation(k)); %#ok<AGROW>
    end
end
T=struct2table(rows,"AsArray",true);
end
function T=localLimitations(cfg)
kpi=string(cfg.outputs.sls_kpis(:));
T=table(kpi,repmat("NOT_EVALUATED",numel(kpi),1), ...
    repmat("Requested KPI requires SLS; it is not inferred from link-level evidence.",numel(kpi),1), ...
    'VariableNames',{'Item','EvidenceClass','Limitation'});
extra=table(["common_evm";"controlled_full_sweep";"encoded_uci_all_modes"; ...
    "multislot_fading_lls"],["NOT_EVALUATED";"NOT_EVALUATED";"NOT_EVALUATED";"NOT_EVALUATED"], ...
    ["Exact agreed 6GR EVM is not present/verified."; ...
    "Publication counts and all controlled matrix dimensions have not run."; ...
    "No error-free substitution was made for missing encoded UCI points."; ...
    "Analytical multi-slot results are not relabeled as waveform LLS."], ...
    'VariableNames',{'Item','EvidenceClass','Limitation'});
T=[T;extra];
end
function localManifest(summary,cfg,prov,context,mode)
manifest=struct("SchemaVersion","sixgr.csi.tdoc.run/v1","RunId",char(context.RunId), ...
    "Mode",char(mode),"ConfigSHA256",char(prov.ConfigSHA256), ...
    "ConfigSources",{cellstr(prov.SourceFiles)},"GitCommit",char(context.GitCommit), ...
    "GitWorktreeDirty",localDirty(),"MATLABRelease",version("-release"), ...
    "CommonEVMVerified",logical(cfg.identity.common_evm_verified), ...
    "EvidenceClasses",{cellstr(sixgr.csi.EvidenceClass.allowed())}, ...
    "Summary",summary,"CreatedUTC",char(datetime("now","TimeZone","UTC")));
sixgr.util.jsonWrite(fullfile(summary.RunFolder,"manifests","run_manifest.json"),manifest);
end
function tf=localDirty()
[~,x]=system("git status --porcelain"); tf=strlength(strtrim(string(x)))>0;
end
function localSummary(folder,s,registry,mode)
fid=fopen(fullfile(folder,"run_summary.md"),"w","n","UTF-8");
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,"# RAN1 10.5.3.1 DL-CSI %s summary\n\n",mode);
fprintf(fid,"- Artifact audit: **%s** (%d checks)\n",localPass(s.AuditPassed),s.AuditChecks);
fprintf(fid,"- CSV: %d; PNG: %d; figures: %d\n",s.CSVCount,s.PNGCount,s.FigureCount);
fprintf(fid,"- PDF: %d; semantic figures: **%s**\n",s.PDFCount,localPass(s.SemanticFigurePassed));
fprintf(fid,"- High-port OFDM points: %d; PDSCH transport blocks: %d\n",s.HighPortPoints,s.PDSCHTransportBlocks);
fprintf(fid,"- Common EVM verified: %d; publication qualified: %d\n\n",s.CommonEVMVerified,s.PublicationQualified);
fprintf(fid,"This run contains bounded real-waveform, procedure, sanity and analytical "+ ...
    "evidence under their explicit classes. It is not a common-EVM or SLS result.\n\n");
fprintf(fid,"- Analytical regression: executed in focused unit gate\n");
fprintf(fid,"- Controlled waveform LLS: bounded matrix only\n");
fprintf(fid,"- Procedure result: bounded deterministic/stochastic evidence\n");
fprintf(fid,"- SLS-required gaps: retained in limitations.csv\n");
fprintf(fid,"- Full D/E/I/J matrices: not complete; controlled mode remains fail-closed\n\n");
fprintf(fid,"| Group | Evidence | Status | Quantitative TDoc eligible |\n|---|---|---|---|\n");
for k=1:height(registry)
    fprintf(fid,"| %s | %s | %s | %d |\n",registry.ScenarioGroup(k), ...
        registry.EvidenceClasses(k),registry.ExecutionStatus(k),registry.QuantitativeTDocEligible(k));
end
end
function value=localPass(tf)
if tf, value="PASS"; else, value="FAIL"; end
end
