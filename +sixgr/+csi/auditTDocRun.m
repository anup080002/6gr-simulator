function [audit,passed]=auditTDocRun(runFolder)
%AUDITTDOCRUN Fail-closed schema, evidence, fallback and image audit.
runFolder=string(char(java.io.File(char(runFolder)).getCanonicalPath()));
rows=repmat(localRow(),0,1);
csv=dir(fullfile(runFolder,"**","*.csv"));
csv=csv(~strcmpi(string({csv.name}),"artifact_audit.csv"));
observedNames=string({csv.name});
required=localRequiredCSVNames(); missing=setdiff(required,observedNames);
[uniqueNames,~,nameIndex]=unique(observedNames);
nameCounts=accumarray(nameIndex(:),1);
duplicateNames=uniqueNames(nameCounts>1);
contractOk=isempty(missing)&&isempty(duplicateNames);
rows(end+1,1)=struct("Artifact","csv/**/*", ...
    "Check","required_csv_contract","Pass",contractOk, ...
    "Details","required="+numel(required)+" missing="+strjoin(missing,"|")+ ...
        " duplicate_names="+strjoin(unique(duplicateNames),"|"));
for k=1:numel(csv)
    path=string(fullfile(csv(k).folder,csv(k).name));
    rel=extractAfter(path,strlength(runFolder+filesep));
    ok=true; detail="";
    try
        T=readtable(path,"Delimiter",",","VariableNamingRule","preserve");
        ok=height(T)>=1 && width(T)>=1;
        detail="rows="+height(T)+" columns="+width(T);
        if ismember("EvidenceClass",string(T.Properties.VariableNames))
            evidence=upper(string(T.EvidenceClass));
            invalid=~ismember(evidence,[sixgr.csi.EvidenceClass.allowed(), ...
                sixgr.csi.EvidenceClass.allowedFigures()]);
            ok=ok&&~any(invalid); detail=detail+" invalid_evidence="+nnz(invalid);
        end
        % Primary evidence of every class is fail-closed. Procedure and
        % analytical tables are not allowed to hide a fallback merely
        % because they are outside the lls/ subfolder.
        if startsWith(rel,"csv"+filesep) && ...
                ismember("FallbackUsed",string(T.Properties.VariableNames))
            fallback=localLogical(T.FallbackUsed); ok=ok&&~any(fallback);
            detail=detail+" fallback_rows="+nnz(fallback);
        end
    catch cause
        ok=false; detail=string(cause.identifier)+": "+string(cause.message);
    end
    rows(end+1,1)=struct("Artifact",rel,"Check","csv_schema_truth", ...
        "Pass",ok,"Details",detail); %#ok<AGROW>
end
manifestPath=fullfile(runFolder,"manifests","figure_manifest.csv");
if exist(manifestPath,"file")==2
    F=readtable(manifestPath,"Delimiter",",","VariableNamingRule","preserve");
    hashes=string(F.PNGSha256);
    keyOk=numel(unique(string(F.FigureId)))==height(F) && ...
        numel(unique(string(F.PNGPath)))==height(F);
    rows(end+1,1)=struct("Artifact","manifests/figure_manifest.csv", ...
        "Check","figure_manifest_unique_keys","Pass",keyOk, ...
        "Details","rows="+height(F)); %#ok<AGROW>
    for k=1:height(F)
        imagePath=fullfile(runFolder,string(F.PNGPath(k)));
        pdfPath=fullfile(runFolder,string(F.VectorPath(k)));
        ok=exist(imagePath,"file")==2 && exist(pdfPath,"file")==2 && ...
            logical(F.NonBlankCheck(k)) && ...
            logical(F.DataReplayCheck(k)) && string(F.Status(k))=="PASS";
        if ok
            info=imfinfo(imagePath); ok=info.Width==F.WidthPx(k)&&info.Height==F.HeightPx(k) && ...
                sixgr.csi.fileSHA256(imagePath)==string(F.PNGSha256(k)) && ...
                sixgr.csi.fileSHA256(pdfPath)==string(F.PDFSha256(k)) && ...
                string(F.SemanticAuditStatus(k))=="PASS";
        end
        rows(end+1,1)=struct("Artifact",string(F.PNGPath(k)), ...
            "Check","png_manifest_replay","Pass",ok, ...
            "Details","figure="+string(F.FigureId(k))); %#ok<AGROW>
    end
    uniqueHashes=all(strlength(hashes)==64)&&numel(unique(hashes))==numel(hashes);
    rows(end+1,1)=struct("Artifact","figures/*.png", ...
        "Check","png_hash_uniqueness","Pass",uniqueHashes, ...
        "Details","unique="+numel(unique(hashes))+" total="+numel(hashes)); %#ok<AGROW>
else
    rows(end+1,1)=struct("Artifact","manifests/figure_manifest.csv", ...
        "Check","figure_manifest","Pass",false,"Details","missing");
end
audit=struct2table(rows,"AsArray",true); passed=~isempty(rows)&&all(audit.Pass);
end

