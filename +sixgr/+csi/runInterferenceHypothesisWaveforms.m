function out=runInterferenceHypothesisWaveforms(cfg,provenance)
%RUNINTERFERENCEHYPOTHESISWAVEFORMS Real two-occasion covariance-age PDSCH.
[llsCfg,llsProv]=sixgr.lls.loadConfig( ...
    string(cfg.execution.pdsch_interference_anchor_config));
llsCfg.simulation.minTransportBlocks=1;
llsCfg.simulation.maxTransportBlocks=2;
llsCfg.simulation.minBlockErrors=3;
llsCfg=sixgr.lls.validateConfig(llsCfg,"ConfigPath",llsProv.ConfigPath);
hash=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(llsCfg),"UTF-8"))));
phy=sixgr.lls.buildPHYConfig(llsCfg,double(llsCfg.simulation.snrDb(1)));
[row1,d1]=sixgr.lls.runPDSCHTransportBlock(llsCfg,phy,hash,1,1, ...
    "CaptureDiagnostic",true);
[row2,d2]=sixgr.lls.runPDSCHTransportBlock(llsCfg,phy,hash,1,2, ...
    "CaptureDiagnostic",true);
[R1,cov1]=sixgr.phy.rx.estimateInterferenceCovarianceIRC( ...
    d1.Rx.RxGrid,d1.Rx.ChannelEstimate,d1.Rx.DMRSIndices, ...
    d1.Rx.DMRSSymbols,d1.NoiseInfo.GridNoiseVariance, ...
    "Slot",0,"CovarianceID","CSI-TDOC-I0");
[R2,cov2]=sixgr.phy.rx.estimateInterferenceCovarianceIRC( ...
    d2.Rx.RxGrid,d2.Rx.ChannelEstimate,d2.Rx.DMRSIndices, ...
    d2.Rx.DMRSSymbols,d2.NoiseInfo.GridNoiseVariance, ...
    "Slot",1,"CovarianceID","CSI-TDOC-I1");
if isempty(R1) || isempty(R2) || ~cov1.Valid || ~cov2.Valid
    error("sixgr:csi:MissingMeasuredInterferenceCovariance", ...
        "Both real interference occasions must yield receiver DM-RS residual "+ ...
        "covariance evidence (occasion 1: %s; occasion 2: %s).", ...
        string(cov1.NAReason),string(cov2.NAReason));
end
sampleCount=double(cov1.SampleCount);
if ~(isfinite(sampleCount)&&sampleCount>=1), sampleCount=size(d1.Tx.DMRSIndices,1); end
state=sixgr.phy.mimo.InterferenceCovarianceState(R1, ...
    CovarianceID="CSI-TDOC-I0",SampleCount=max(1,round(sampleCount)), ...
    MinSamples=1,Slot=0,MaxAgeSlots=max(double(cfg.interference_age.ages_slots)), ...
    SourceResource="previous_occasion_dmrs_residual", ...
    IncludesNoise=true);
age=max(1,min(4,max(double(cfg.interference_age.ages_slots))));
state.validateAt(age);
tx=d2.Tx;
[fresh,~]=localReplay(d2.RxWaveform,phy,tx,llsCfg,d2.NoiseInfo,R2, ...
    "current_occasion_dmrs_residual");
[stale,~]=localReplay(d2.RxWaveform,phy,tx,llsCfg,d2.NoiseInfo,state.Matrix, ...
    "previous_occasion_dmrs_residual");
freshSINR=double(sixgr.util.structGet(fresh,"PostEqSINR_dB",NaN));
staleSINR=double(sixgr.util.structGet(stale,"PostEqSINR_dB",NaN));
if ~all(isfinite([freshSINR staleSINR]))
    error("sixgr:csi:MissingInterferenceSINR", ...
        "Fresh and previous-occasion covariance receivers must report measured SINR.");
end
policies=["refreshed_actual_occasion";"previous_occasion_age_"+string(age)];
crc=[logical(fresh.CRCError);logical(stale.CRCError)];
sinr=[freshSINR;staleSINR]; covarianceSource=[ ...
    string(cov2.Source);"previous_occasion_dmrs_residual"];
receiverCovarianceSource=[string(sixgr.util.structGet(fresh, ...
    "InterferenceCovarianceSource",""));string(sixgr.util.structGet(stale, ...
    "InterferenceCovarianceSource",""))];
covarianceApplied=[logical(sixgr.util.structGet(fresh, ...
    "InterferenceCovarianceAvailable",false));logical(sixgr.util.structGet(stale, ...
    "InterferenceCovarianceAvailable",false))];
covarianceIncludesNoise=[logical(sixgr.util.structGet(fresh, ...
    "EqualizerCovarianceIncludesNoise",false));logical(sixgr.util.structGet(stale, ...
    "EqualizerCovarianceIncludesNoise",false))];
noiseAddedExactlyOnce=[logical(sixgr.util.structGet(fresh, ...
    "EqualizerNoiseAddedExactlyOnce",false));logical(sixgr.util.structGet(stale, ...
    "EqualizerNoiseAddedExactlyOnce",false))];
equalizerType=[string(sixgr.util.structGet(fresh,"EqualizerType","")); ...
    string(sixgr.util.structGet(stale,"EqualizerType",""))];
if ~all(covarianceApplied) || ~all(covarianceIncludesNoise) || ...
        ~all(noiseAddedExactlyOnce) || any(strlength(equalizerType)==0)
    error("sixgr:csi:InterferenceCovarianceNotApplied", ...
        "Both covariance policies must be consumed by the production equalizer with noise counted exactly once. applied=%s includes_noise=%s noise_once=%s equalizers=%s", ...
        mat2str(covarianceApplied.'),mat2str(covarianceIncludesNoise.'), ...
        mat2str(noiseAddedExactlyOnce.'),strjoin(equalizerType,"|"));
end
point=table(policies,[0;age],repmat(row2.TargetSNRdB,2,1), ...
    repmat(row2.MeasuredPreEqualizationSINRdB,2,1),sinr,crc, ...
    double(~crc)*double(row2.TransportBlockSizeBits),covarianceSource, ...
    [string(sixgr.phy.mimo.MatrixContract.digest(R2)); ...
     string(sixgr.phy.mimo.MatrixContract.digest(state.Matrix))], ...
    receiverCovarianceSource,covarianceApplied,covarianceIncludesNoise, ...
    noiseAddedExactlyOnce,equalizerType, ...
    repmat(row2.InterferenceSource,2,1),repmat("none",2,1), ...
    repmat("LLS_CONTROLLED",2,1),repmat("PASS",2,1), ...
    'VariableNames',{'CovariancePolicy','InterferenceAgeSlots', ...
    'ConfiguredSNRdB','MeasuredPreEqSINRdB','PostEqSINRdB','CRCError', ...
    'DeliveredBits','CovarianceSource','CovarianceSHA256', ...
    'ReceiverCovarianceSource','CovarianceApplied', ...
    'CovarianceIncludesNoise','NoiseAddedExactlyOnce','EqualizerType', ...
    'InterferenceSource','ApproximationMode','EvidenceClass','Status'});
sinrError=point(:,["CovariancePolicy","InterferenceAgeSlots", ...
    "PostEqSINRdB","EvidenceClass","Status"]);
sinrError.ReferencePostEqSINRdB(:)=freshSINR;
sinrError.SINRErrorDb=sinrError.PostEqSINRdB-freshSINR;
thresholds=double(cfg.csi.bounded_flow.cqi_thresholds_db(:));
freshCQI=localCQI(freshSINR,thresholds);
sinrError.CQI=arrayfun(@(x)localCQI(x,thresholds),sinrError.PostEqSINRdB);
sinrError.ReferenceCQI(:)=freshCQI;
sinrError.CQIError=sinrError.CQI-freshCQI;
bler=point(:,["CovariancePolicy","InterferenceAgeSlots","CRCError", ...
    "DeliveredBits","EvidenceClass","Status"]);
bler.TransportBlocks(:)=1; bler.BlockErrors=double(bler.CRCError);
bler.BLER=bler.BlockErrors;
out=struct("Points",point,"SINRError",sinrError, ...
    "CQIError",sinrError,"BLER",bler, ...
    "SuiteConfigSHA256",string(provenance.ConfigSHA256), ...
    "AnchorConfigSHA256",string(llsProv.ConfigSHA256), ...
    "PriorTrial",struct2table(row1));
end

function [rx,info]=localReplay(rxWaveform,phy,tx,llsCfg,noiseInfo,Rint,source)
[rx,info]=sixgr.phy.dl.PDSCH_Rx(rxWaveform,phy, ...
    "Carrier",tx.Carrier,"PDSCH",tx.PDSCH, ...
    "PDSCHIndices",tx.PDSCHIndices, ...
    "TransportBlockSize",tx.TransportBlockSize, ...
    "TargetCodeRate",tx.TargetCodeRate,"RV",tx.RV, ...
    "CodingPlan",tx.CodingPlans,"NoiseVar",noiseInfo.GridNoiseVariance, ...
    "NoiseVarDomain","grid", ...
    "MaxIterations",double(llsCfg.receiver.ldpcMaxIterations), ...
    "Algorithm",char(string(llsCfg.receiver.ldpcAlgorithm)), ...
    "PrecodingMatrix",tx.PrecodeInfo.MatrixPorts, ...
    "InterferenceCovariance",Rint, ...
    "InterferenceCovarianceSource",source, ...
    "InterferenceCovarianceIncludesNoise",true, ...
    "ExecutionProfile","phy_calibration","CompactOutput",false, ...
    "FastAWGNPath",false,"SkipTimingEstimate",true);
end

function value=localCQI(sinrDb,thresholds)
value=find(sinrDb>=thresholds,1,"last")-1;
value=max(0,min(numel(thresholds)-1,value));
end
