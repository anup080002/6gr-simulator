function [inventory,gaps]=buildRepositoryInventory(repoRoot)
%BUILDREPOSITORYINVENTORY Inspect reusable production components.
arguments
    repoRoot (1,1) string
end
patterns=[ ...
    "runDLPDSCHThroughput.m";"TR38901Plus.m";"ChannelFactory.m"; ...
    "CSIRSResourceEngine.m";"SharedDMRSEngine.m";"CSIReportSerializer.m"; ...
    "CSIReportDecoder.m";"MeasurementStateStore.m";"OLLAState.m"; ...
    "buildCSIFeedback.m";"selectPMI.m";"exportLinkKPIs.m"; ...
    "runPDSCHTransportBlock.m";"PDSCH_Tx.m";"PDSCH_Rx.m"; ...
    "EvidenceClass.m";"loadTDocConfig.m";"validateTDocConfig.m"; ...
    "runProcedureScenarios.m";"runCanonicalFlowTrial.m"; ...
    "runInterferenceHypothesisWaveforms.m"; ...
    "runEnergyHypothesisWaveforms.m";"HighPortCSIRSMapper.m"; ...
    "OCCFactory.m";"FigureManifest.m";"auditTDocRun.m"];
rows=repmat(localInventoryRow(),numel(patterns),1);
allFiles=dir(fullfile(repoRoot,"**","*")); allFiles=allFiles(~[allFiles.isdir]);
allNames=string({allFiles.name});
for k=1:numel(patterns)
    idx=find(allNames==patterns(k),1);
    rows(k).Component=erase(patterns(k),".m");
    if isempty(idx)
        rows(k).Path=""; rows(k).Exists=false; rows(k).ReuseStatus="MISSING";
    else
        rows(k).Path=string(fullfile(allFiles(idx).folder,allFiles(idx).name));
        rows(k).Exists=true; rows(k).ReuseStatus="REUSE";
    end
end
inventory=struct2table(rows,"AsArray",true);

requirements=[ ...
    "TRUTH-001","0","Evidence taxonomy and no silent fallback","EvidenceClass", ...
        "Bounded taxonomy/audit implemented; publication convergence remains a full-run gate","IMPLEMENTED_BOUNDED"; ...
    "CFG-001","2","Layered YAML and resolved configuration","validateTDocConfig", ...
        "No bounded gap; full matrix profiles still require controlled overlays","IMPLEMENTED_BOUNDED"; ...
    "PHY-001","3","Production PDSCH/DMRS/HARQ chain","runPDSCHTransportBlock", ...
        "PDSCH and encoded UCI are wired; HARQ matrix remains controlled-run work","REUSED_AND_WIRED"; ...
    "A-001","4","CSI state/CPU lifecycle","runProcedureScenarios", ...
        "Bounded procedure matrix executes; publication-scale state/CPU matrix remains","IMPLEMENTED_BOUNDED"; ...
    "B-001","5","DMRS reference-state refinement","runCanonicalFlowTrial", ...
        "Bounded PDSCH/DMRS delta and encoded feedback execute; full CDL/rank matrix remains","IMPLEMENTED_BOUNDED"; ...
    "C-001","6","Interference hypothesis age","runInterferenceHypothesisWaveforms", ...
        "Two real occasions execute; statistical age/DIR/channel matrix remains","IMPLEMENTED_BOUNDED"; ...
    "D-001","7","Early CSI causality","runProcedureScenarios", ...
        "Procedure is present; every early-CSI variant still needs causally paired PDSCH trials","PARTIAL_FULL_MATRIX"; ...
    "E-001","8","Bounded event CSI","runCanonicalFlowTrial", ...
        "Encoded event UCI executes; threshold/hysteresis/TTT PDSCH campaign remains","PARTIAL_FULL_MATRIX"; ...
    "F-001","9","Multi-hypothesis CSI","runEnergyHypothesisWaveforms", ...
        "Four measured-CSI hybrid PDSCH hypotheses execute; repeated statistical matrix remains","IMPLEMENTED_BOUNDED"; ...
    "G-001","10","128/256/512-port CSI-RS","HighPortCSIRSMapper", ...
        "All bounded high-port OFDM points execute; controlled SNR/channel matrix remains","IMPLEMENTED_BOUNDED"; ...
    "H-001","11","CSI-RS sharing/identity","HighPortCSIRSMapper", ...
        "Absolute resource maps execute; collision/channel stress matrix remains","IMPLEMENTED_BOUNDED"; ...
    "I-001","12","Walsh/DFT OCC CDM8/16/32/64","OCCFactory", ...
        "All OCC lengths/families execute; estimate-conditioned PDSCH OCC matrix remains","PARTIAL_FULL_MATRIX"; ...
    "J-001","13","Multi-slot/multi-RB CSI-RS","HighPortCSIRSMapper", ...
        "M1=2 estimate-conditioned PDSCH executes; Case A/B, M2 and stress matrix remain","PARTIAL_FULL_MATRIX"; ...
    "ART-001","14-18","CSV replay figures and artifact audit","auditTDocRun", ...
        "Bounded CSV/image/hash audit implemented; controlled artifacts await full execution","IMPLEMENTED_BOUNDED"];
grows=repmat(localGapRow(),size(requirements,1),1);
for k=1:size(requirements,1)
    component=requirements(k,4);
    present=component~="" && any(contains(inventory.Component,component) | ...
        contains(inventory.Path,component));
    requestedStatus=requirements(k,6);
    status=localIf(present,requestedStatus,"MISSING_CAPABILITY");
    grows(k)=struct("RequirementId",requirements(k,1), ...
        "TDocSection",requirements(k,2),"ExistingComponent",component, ...
        "ExistingFile",localPathFor(inventory,component), ...
        "ReusePlan",localIf(present,"canonical owner present and wired", ...
            "implement missing canonical owner"),"MissingWork",requirements(k,5), ...
        "Risk",localIf(contains(status,"PARTIAL"),"medium", ...
            localIf(present,"low","high")),"Status",status);
end
gaps=struct2table(grows,"AsArray",true);
end

function row=localInventoryRow()
row=struct("Component","","Path","","Exists",false,"ReuseStatus","");
end
function row=localGapRow()
row=struct("RequirementId","","TDocSection","","ExistingComponent","", ...
    "ExistingFile","","ReusePlan","","MissingWork","","Risk","","Status","");
end
function value=localPathFor(T,component)
if component=="", value=""; return; end
idx=find(contains(T.Component,component)|contains(T.Path,component),1);
if isempty(idx), value=""; else, value=string(T.Path(idx)); end
end
function value=localIf(tf,a,b)
if tf, value=a; else, value=b; end
end
