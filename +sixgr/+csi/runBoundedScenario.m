function out=runBoundedScenario(cfg,provenance)
%RUNBOUNDEDSCENARIO Execute bounded genuine OFDM CSI-RS/PDSCH evidence.
ports=double(cfg.csirs.port_counts(:)); modes=string(cfg.power.normalization_modes(:));
snr=double(cfg.simulation.bounded_snr_points_db(2));
rows=[]; maps=[]; seedBase=double(cfg.reproducibility.base_seed)+100;
flowSource=[];
nRealizations=double(cfg.simulation.bounded_channel_realizations_per_point);
useParallel=logical(sixgr.util.structGet(cfg,"execution.parallel_enabled",false)) && ...
    nRealizations>1 && license("test","Distrib_Computing_Toolbox");
if useParallel
    workers=double(sixgr.util.structGet(cfg,"execution.maximum_workers",4));
    pool=gcp("nocreate");
    if isempty(pool)
        parpool("Processes",workers);
    elseif pool.NumWorkers>workers
        error("sixgr:csi:ParallelPoolExceedsConfiguredWorkers", ...
            "The active pool has %d workers but YAML limits this campaign to %d.", ...
            pool.NumWorkers,workers);
    end
end
for p=ports.'
    for mode=modes.'
        L=double(cfg.csirs.cdm_sizes(1));
        pairedSeeds=seedBase+p*100000+(1:nRealizations);
        result=sixgr.phy.refsig.HighPortCSIRSMapper.runWaveformPoint( ...
            cfg,p,L,"walsh",1,mode,snr,pairedSeeds(1));
        pointRows=cell(nRealizations,1);
        pointRows{1}=localHighPortRow(result,p,L,mode,snr,1,nRealizations);
        if nRealizations>1
            if useParallel
                parfor trial=2:nRealizations
                    trialResult=sixgr.phy.refsig.HighPortCSIRSMapper.runWaveformPoint( ...
                        cfg,p,L,"walsh",1,mode,snr,pairedSeeds(trial));
                    pointRows{trial}=localHighPortRow( ...
                        trialResult,p,L,mode,snr,trial,nRealizations);
                end
            else
                for trial=2:nRealizations
                    trialResult=sixgr.phy.refsig.HighPortCSIRSMapper.runWaveformPoint( ...
                        cfg,p,L,"walsh",1,mode,snr,pairedSeeds(trial));
                    pointRows{trial}=localHighPortRow( ...
                        trialResult,p,L,mode,snr,trial,nRealizations);
                end
            end
        end
        rows=[rows;vertcat(pointRows{:})]; %#ok<AGROW>
        fprintf("CSI-RS waveform point complete: ports=%d power=%s realizations=%d\n", ...
            p,mode,nRealizations);
        m=result.Plan.Map; m.TxPorts(:)=p; m.PowerNormalization(:)=mode;
        maps=[maps;m]; %#ok<AGROW>
        if p==double(cfg.csirs.port_counts(1)) && mode=="fixed_per_port_epre"
            flowSource=result;
        end
    end
end

% No-noise exact mapper/despreader gates for every requested OCC length.
occRows=[];
occPerformance=[];
for L=double(cfg.csirs.cdm_sizes(:)).'
    for family=string(cfg.csirs.occ_families(:)).'
        result=sixgr.phy.refsig.HighPortCSIRSMapper.runWaveformPoint(cfg,L,L,family,1, ...
            "fixed_per_port_epre",120,seedBase+L+double(family=="dft"));
        occRows=[occRows;table(L,family,result.NMSE,result.SGCS, ...
            result.Seed,"LLS_CONTROLLED","PASS",'VariableNames', ...
            {'CDMSize','OCCFamily','NMSELinear','SGCS','Seed', ...
            'EvidenceClass','Status'})]; %#ok<AGROW>
        finite=sixgr.phy.refsig.HighPortCSIRSMapper.runWaveformPoint( ...
            cfg,L,L,family,1,"fixed_per_port_epre", ...
            double(cfg.multislot.bounded_snr_db),seedBase+3000+L+ ...
            double(family=="dft"),"ChipPhaseDeg", ...
            double(cfg.occ.focal_phase_deg_per_chip(end)));
        occPerformance=[occPerformance;table(L,family, ...
            double(cfg.occ.focal_phase_deg_per_chip(end)), ...
            double(cfg.multislot.bounded_snr_db),finite.NMSE, ...
            finite.NMSEdB,finite.SGCS,finite.GridNoiseVariance, ...
            string(finite.ExecutionBackend),"none","LLS_CONTROLLED","PASS", ...
            'VariableNames',{'CDMSize','OCCFamily','PhaseDegPerChip', ...
            'SNRdB','NMSELinear','NMSEdB','SGCS','GridNoiseVariance', ...
            'ExecutionBackend','ApproximationMode','EvidenceClass','Status'})]; %#ok<AGROW>
    end
end

% Production PDSCH/DL-SCH anchor. This is a controlled waveform run, not a
% common-EVM result, and each row is directly produced by the existing Tx/Rx.
[llsCfg,llsProv]=sixgr.lls.loadConfig(string(cfg.execution.pdsch_anchor_config));
llsCfg.simulation.snrDb=double(cfg.simulation.bounded_snr_points_db(:).');
llsCfg.simulation.minTransportBlocks=double(cfg.simulation.bounded_transport_blocks_per_point);
llsCfg.simulation.maxTransportBlocks=double(cfg.simulation.bounded_transport_blocks_per_point);
llsCfg.simulation.minBlockErrors=double(cfg.simulation.bounded_transport_blocks_per_point)+1;
effectiveHash=string(sixgr.util.sha256Hex(uint8(unicode2native(jsonencode(llsCfg),"UTF-8"))));
parts=cell(numel(llsCfg.simulation.snrDb),1);
for s=1:numel(llsCfg.simulation.snrDb)
    phy=sixgr.lls.buildPHYConfig(llsCfg,double(llsCfg.simulation.snrDb(s)));
    point=cell(llsCfg.simulation.maxTransportBlocks,1);
    if useParallel && llsCfg.simulation.maxTransportBlocks>1
        parfor t=1:llsCfg.simulation.maxTransportBlocks
            [row,~]=sixgr.lls.runPDSCHTransportBlock(llsCfg,phy,effectiveHash,s,t, ...
                "CaptureDiagnostic",false);
            row.EvidenceClass="LLS_CONTROLLED";
            row.SuiteConfigSHA256=string(provenance.ConfigSHA256);
            row.AnchorConfigSHA256=string(llsProv.ConfigSHA256);
            row.FallbackUsed=false;
            row.FallbackReason="";
            point{t}=struct2table(row);
        end
    else
        for t=1:llsCfg.simulation.maxTransportBlocks
            [row,~]=sixgr.lls.runPDSCHTransportBlock(llsCfg,phy,effectiveHash,s,t, ...
                "CaptureDiagnostic",false);
            row.EvidenceClass="LLS_CONTROLLED";
            row.SuiteConfigSHA256=string(provenance.ConfigSHA256);
            row.AnchorConfigSHA256=string(llsProv.ConfigSHA256);
            row.FallbackUsed=false;
            row.FallbackReason="";
            point{t}=struct2table(row);
        end
    end
    parts{s}=vertcat(point{:});
    fprintf("PDSCH anchor point complete: SNR=%g dB transport_blocks=%d\n", ...
        double(llsCfg.simulation.snrDb(s)),height(parts{s}));
end
pdsch=vertcat(parts{:});
summary=[];
for s=1:numel(llsCfg.simulation.snrDb)
    sub=pdsch(pdsch.SNRIndex==s,:); n=height(sub); errors=sum(sub.CRCError);
    [low,high]=sixgr.lls.stats.wilsonInterval(errors,n,double(cfg.reproducibility.confidence_level));
    summary=[summary;table(double(llsCfg.simulation.snrDb(s)),n,errors, ...
        errors/n,low,high,sum(sub.TransportBlockSizeBits(~sub.CRCError)), ...
        mean(sub.PostEqSINRdB,"omitnan"),"LLS_CONTROLLED","PASS", ...
        'VariableNames',{'SNRdB','N','BlockErrors','BLER','CI95Low','CI95High', ...
        'DeliveredBits','MeanPostEqSINRdB','EvidenceClass','Status'})]; %#ok<AGROW>
end

% Reference-state-associated DMRS refinement consumes the actual receiver
% post-equalization SINR from the production PDSCH trials.
reference=mean(pdsch.PostEqSINRdB(pdsch.SNRIndex==1),"omitnan");
dmrs=pdsch(:,intersect(["ScenarioId","SNRIndex","TrialIndex","ChannelSeed", ...
    "CRCError","PostEqSINRdB","PostEqSINRSource","ChannelEstimateSource", ...
    "DMRSRE","EvidenceClass","FallbackUsed","FallbackReason"], ...
    string(pdsch.Properties.VariableNames),"stable"));
dmrs.ReferenceStateSINRdB(:)=reference;
dmrs.DMRSCQIDeltaDb=dmrs.PostEqSINRdB-reference;
dmrs.ReferenceStateValid=isfinite(dmrs.PostEqSINRdB) & abs(dmrs.DMRSCQIDeltaDb)<=6;
dmrs.LayerImbalanceDb(:)=0;
dmrs.RankDownIndication(:)=false;
dmrs.Status(:)="PASS";

if isempty(flowSource)
    error("sixgr:csi:CanonicalFlowSourceUnavailable", ...
        "The configured high-port matrix did not produce the bounded flow source point.");
end
canonical=sixgr.csi.runCanonicalFlowTrial(cfg,flowSource,pdsch);
multi=sixgr.phy.refsig.HighPortCSIRSMapper.runMultiSlotWaveformPoint(cfg, ...
    "M1",double(cfg.multislot.bounded_m1), ...
    "PortCount",double(cfg.multislot.bounded_port_count), ...
    "CDMSize",double(cfg.multislot.bounded_cdm_size), ...
    "OCCFamily","walsh","Density",1, ...
    "PowerNormalization","fixed_per_port_epre", ...
    "SNRdB",double(cfg.multislot.bounded_snr_db), ...
    "SpeedKmph",double(cfg.multislot.bounded_speed_kmph), ...
    "PhaseIncrementDeg",double(cfg.multislot.bounded_phase_increment_deg), ...
    "Seed",seedBase+9000);
multi.PDSCHPerformance=localRunMultiSlotPDSCH(cfg,multi,provenance);
energy=sixgr.csi.runEnergyHypothesisWaveforms(cfg,provenance);
interference=sixgr.csi.runInterferenceHypothesisWaveforms(cfg,provenance);

out=struct("HighPort",rows,"ResourceMap",maps,"OCC",occRows, ...
    "PDSCHTrials",pdsch,"PDSCHSummary",summary,"DMRSRefinement",dmrs, ...
    "CanonicalFlow",canonical,"MultiSlot",multi, ...
    "OCCPerformance",occPerformance,"EnergyHypotheses",energy, ...
    "Interference",interference);
end

function row=localHighPortRow(result,p,L,mode,snr,trial,nTrials)
row=table(p,L,"walsh",1,mode,snr,result.ReceiverAntennas,trial,nTrials, ...
    result.NMSE,result.NMSEdB,result.SGCS,result.PerPortEPRE, ...
    result.TotalCSIRSPower,result.GridNoiseVariance, ...
    result.SampleNoiseVariance,result.SampleToGridNoiseVarianceGain, ...
    string(result.NoiseVarianceDomain),string(result.NoiseSource), ...
    result.Seed,result.ChannelSeed,result.NoiseSeed, ...
    string(result.Plan.MapSHA256),string(result.FDTDSplit), ...
    string(result.Estimator),string(result.EstimatorSource), ...
    string(result.ExecutionBackend),"none","LLS_CONTROLLED","PASS", ...
    'VariableNames',{'TxPorts','CDMSize','OCCFamily','Density', ...
    'PowerNormalization','SNRdB','RxAntennas','TrialIndex', ...
    'ConfiguredTrials','NMSELinear','NMSEdB','SGCS','PerPortEPRE', ...
    'TotalCSIRSPower','GridNoiseVariance','SampleNoiseVariance', ...
    'SampleToGridNoiseVarianceGain','NoiseVarianceDomain','NoiseSource', ...
    'Seed','ChannelSeed','NoiseSeed','ResourceMapSHA256','FDTDSplit', ...
    'Estimator','EstimatorSource','ExecutionBackend','ApproximationMode', ...
    'EvidenceClass','Status'});
end

function performance=localRunMultiSlotPDSCH(cfg,multi,provenance)
% Apply each multi-slot receiver estimate as a measured physical-array beam
% to the same coded PDSCH transport block and channel snapshot.
[llsCfg,llsProv]=sixgr.lls.loadConfig(string(cfg.execution.pdsch_anchor_config));
snrDb=double(cfg.multislot.bounded_snr_db);
llsCfg.simulation.snrDb=snrDb;
llsCfg.simulation.minTransportBlocks=1;
llsCfg.simulation.maxTransportBlocks=1;
llsCfg.simulation.minBlockErrors=2;
llsCfg.simulation.statisticalClass="diagnostic_only";
llsCfg=sixgr.lls.validateConfig(llsCfg,"ConfigPath",llsProv.ConfigPath);
phy=sixgr.lls.buildPHYConfig(llsCfg,snrDb);
p=size(multi.ReferenceChannel,2);
estimates={multi.CoherentEstimate;multi.PhaseCorrectedEstimate};
modes=["coherent_uncorrected";"phase_corrected"];
commonTransportBits=[]; performance=[];
seedBase=double(cfg.reproducibility.base_seed)+21000;
for k=1:numel(modes)
    [~,~,V]=svd(estimates{k},"econ"); W=V(:,1); W=W/max(norm(W),eps);
    phyCase=phy;
    phyCase.phy.pdsch.numPorts=1;
    phyCase.phy.pdsch.nPorts=1;
    phyCase.phy.pdsch.numRFChains=1;
    phyCase.phy.pdsch.hybridBeamformingEnabled=true;
    phyCase.phy.pdsch.hybridElementToPortMatrix=W;
    phyCase.phy.nTxAnt=p;
    phyCase.channel.nTxAnt=p;
    phyCase.scenario.bs.nTxAnt=p;
    phyCase.antenna.bs.numElements=p;
    phyCase.antenna.bs.numPorts=1;
    phyCase.antenna.bs.numRFChains=1;
    phyCase.antenna.bs.hybridBeamformingEnabled=true;
    phyCase.antenna.bs.hybridElementToPortMatrix=W;
    txArgs={"ExecutionProfile","phy_calibration","NumTxAnt",p, ...
        "PrecodingMatrix",1,"CompactOutput",false};
    if ~isempty(commonTransportBits)
        txArgs=[txArgs,{"TransportBlockBits",commonTransportBits}]; %#ok<AGROW>
    end
    [tx,~]=sixgr.phy.dl.PDSCH_Tx(phyCase,txArgs{:});
    if isempty(commonTransportBits), commonTransportBits=tx.TransportBlock; end
    desired=tx.Waveform*transpose(multi.ReferenceChannel);
    [rxWaveform,noiseInfo]=sixgr.phy.waveform.addOccupiedREAWGN( ...
        desired,tx.Carrier,snrDb,"Seed",seedBase, ...
        "SignalEnergyPerOccupiedRE",1);
    [rx,~]=sixgr.phy.dl.PDSCH_Rx(rxWaveform,phyCase, ...
        "Carrier",tx.Carrier,"PDSCH",tx.PDSCH, ...
        "PDSCHIndices",tx.PDSCHIndices, ...
        "TransportBlockSize",tx.TransportBlockSize, ...
        "TargetCodeRate",tx.TargetCodeRate,"RV",tx.RV, ...
        "CodingPlan",tx.CodingPlans,"NoiseVar",noiseInfo.GridNoiseVariance, ...
        "NoiseVarDomain","grid", ...
        "MaxIterations",double(llsCfg.receiver.ldpcMaxIterations), ...
        "Algorithm",char(string(llsCfg.receiver.ldpcAlgorithm)), ...
        "PrecodingMatrix",1,"ExecutionProfile","phy_calibration", ...
        "CompactOutput",false,"FastAWGNPath",false, ...
        "SkipTimingEstimate",true);
    tbs=sum(double(tx.TransportBlockSize));
    performance=[performance;table(modes(k),double(multi.Summary.M1(k)),p, ...
        snrDb,true,double(rx.CRCError),double(~rx.CRCError)*tbs, ...
        double(sixgr.util.structGet(rx,"PostEqSINR_dB",NaN)), ...
        string(sixgr.util.structGet(rx,"PostEqSINRSource","")), ...
        string(sixgr.phy.mimo.MatrixContract.digest(W)), ...
        "mean_physical_multislot_channel_snapshot", ...
        "sixgr.phy.dl.PDSCH_Tx_hybrid_element_domain_to_PDSCH_Rx", ...
        "none","LLS_CONTROLLED","PASS", ...
        'VariableNames',{'ReceiverMode','M1','TxPorts','ConfiguredSNRdB', ...
        'PDSCHApplied','CRCError','PDSCHGoodputBits','PostEqSINRdB', ...
        'PostEqSINRSource','PrecoderSHA256','ChannelReference', ...
        'ExecutionBackend','ApproximationMode','EvidenceClass','Status'})]; %#ok<AGROW>
end
performance.SuiteConfigSHA256(:)=string(provenance.ConfigSHA256);
performance.AnchorConfigSHA256(:)=string(llsProv.ConfigSHA256);
end
