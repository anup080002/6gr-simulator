classdef FigureManifest
    %FIGUREMANIFEST CSV-only raster replay for the twenty TDoc figures.

    methods (Static)
        function manifest=replay(runFolder,cfg,context)
            specs=localSpecs(); figureDir=fullfile(runFolder,"figures");
            if ~isfolder(figureDir), mkdir(figureDir); end
            manifestPath=fullfile(runFolder,"manifests","figure_manifest.csv");
            prior=table();
            if exist(manifestPath,"file")==2
                prior=readtable(manifestPath,"Delimiter",",", ...
                    "VariableNamingRule","preserve");
            end
            rows=repmat(localManifestRow(),height(specs),1);
            for k=1:height(specs)
                source=fullfile(runFolder,specs.SourceCsv(k));
                if exist(source,"file")~=2
                    error("sixgr:csi:MissingFigureSource", ...
                        "Figure %s source CSV is missing: %s.",specs.FigureId(k),source);
                end
                data=readtable(source,"Delimiter",",","VariableNamingRule","preserve");
                filterExpression="all_rows";
                if specs.FilterColumn(k)~=""
                    column=specs.FilterColumn(k);
                    if ~ismember(column,string(data.Properties.VariableNames))
                        error("sixgr:csi:MissingFigureFilterColumn", ...
                            "Figure %s filter column %s is absent.", ...
                            specs.FigureId(k),column);
                    end
                    target=str2double(specs.FilterValue(k));
                    values=localNumeric(data.(column));
                    tolerance=1e-12*max(1,abs(target));
                    data=data(abs(values-target)<=tolerance,:);
                    filterExpression=column+"=="+specs.FilterValue(k);
                    if isempty(data)
                        error("sixgr:csi:EmptyFigureFilter", ...
                            "Figure %s filter %s selected no source rows.", ...
                            specs.FigureId(k),filterExpression);
                    end
                end
                [x,y,xName,yName]=localXY(data,specs.XColumn(k),specs.YColumn(k));
                valid=isfinite(x)&isfinite(y);
                if nnz(valid)<1
                    error("sixgr:csi:EmptyFigureData", ...
                        "Figure %s has no finite CSV-backed points.",specs.FigureId(k));
                end
                fig=figure("Visible","off","Color","white","Units","pixels", ...
                    "Position",[50 50 double(cfg.execution.image_width_px) ...
                    double(cfg.execution.image_height_px)]);
                cleanup=onCleanup(@() close(fig)); %#ok<NASGU>
                ax=axes(fig,"Color","white","XColor",[.12 .12 .12], ...
                    "YColor",[.12 .12 .12],"GridColor",[.75 .75 .75], ...
                    "GridAlpha",.55); hold(ax,"on"); grid(ax,"on"); box(ax,"on");
                groups=localGroupLabels(data,specs.GroupColumns(k));
                groupNames=unique(groups(valid),"stable");
                for g=1:numel(groupNames)
                    selected=valid & groups==groupNames(g);
                    displayName=groupNames(g);
                    if specs.Style(k)=="scatter"
                        scatter(ax,x(selected),y(selected),32,"filled", ...
                            "DisplayName",displayName);
                    else
                        [xs,order]=sort(x(selected)); ys=y(selected); ys=ys(order);
                        plot(ax,xs,ys,"o-","LineWidth",1.8,"MarkerSize",5, ...
                            "DisplayName",displayName);
                    end
                end
                if specs.GroupColumns(k)~="" && numel(groupNames)<=12
                    legend(ax,"show","Location","best","Interpreter","none", ...
                        "TextColor",[.12 .12 .12],"Color","white");
                end
                title(ax,specs.Title(k),"Interpreter","none","Color",[.08 .08 .08]);
                xlabel(ax,xName,"Interpreter","none","Color",[.12 .12 .12]);
                ylabel(ax,yName,"Interpreter","none","Color",[.12 .12 .12]);
                png=fullfile(figureDir,specs.FileName(k));
                sixgr.util.exportFigureArtifact(fig,png,"Resolution", ...
                    double(cfg.execution.image_resolution_dpi));
                % MATLAB's PNG writers include run-dependent tIME/text
                % chunks. Strip only volatile metadata so unchanged CSVs
                % and plot code yield byte-identical raster evidence.
                sixgr.csi.canonicalizePNG(png);
                plotted=findobj(ax,"Type","line");
                if isempty(plotted)
                    plotted=findobj(ax,"Type","scatter");
                end
                replay=~isempty(plotted) && nnz(valid)>=1;
                info=imfinfo(png);
                sourceHash=sixgr.csi.fileSHA256(source);
                pngHash=sixgr.csi.fileSHA256(png);
                if ~isempty(prior) && all(ismember(["FigureId", ...
                        "SourceCsvSha256","PNGSha256"], ...
                        string(prior.Properties.VariableNames)))
                    matched=string(prior.FigureId)==specs.FigureId(k) & ...
                        string(prior.SourceCsvSha256)==sourceHash;
                    if nnz(matched)==1 && string(prior.PNGSha256(matched))~=pngHash
                        error("sixgr:csi:NondeterministicFigureReplay", ...
                            "Figure %s changed hash while its source CSV hash was unchanged.", ...
                            specs.FigureId(k));
                    end
                end
                rows(k)=struct("FigureId",specs.FigureId(k),"Title",specs.Title(k), ...
                    "EvidenceClass",specs.EvidenceClass(k), ...
                    "ScenarioIds",specs.ScenarioIds(k), ...
                    "SourceCsv",string(specs.SourceCsv(k)), ...
                    "SourceCsvSha256",sourceHash, ...
                    "PlotScript","sixgr.csi.FigureManifest.replay", ...
                    "XColumns",xName,"YColumns",yName, ...
                    "GroupColumns",specs.GroupColumns(k), ...
                    "FilterExpression",filterExpression, ...
                    "Aggregation","none","PNGPath",string(fullfile("figures",specs.FileName(k))), ...
                    "PNGSha256",pngHash,"VectorPath","", ...
                    "WidthPx",info.Width,"HeightPx",info.Height, ...
                    "NonBlankCheck",std(double(imread(png)),0,"all")>0, ...
                    "DataReplayCheck",replay,"Status",localIf(replay,"PASS","FAIL"), ...
                    "Limitations","Raster-only repository policy; no SVG generated.");
            end
            manifest=struct2table(rows,"AsArray",true);
            sixgr.csi.ResultWriter.write(manifestPath,manifest,context);
        end
    end
end

