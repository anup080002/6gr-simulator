function [x,y,xName,yName]=localXY(T,xName,yName)
names=string(T.Properties.VariableNames);
if xName=="", x=(1:height(T)).'; xName="RowIndex";
elseif any(names==xName), x=localNumeric(T.(xName));
else, error("sixgr:csi:MissingFigureColumn","Missing figure X column %s.",xName); end
if any(names==yName), y=localNumeric(T.(yName));
else, error("sixgr:csi:MissingFigureColumn","Missing figure Y column %s.",yName); end
end
function v=localNumeric(v)
if isnumeric(v)||islogical(v), v=double(v(:)); else, v=str2double(string(v(:))); end
end
function groups=localGroupLabels(T,columns)
if columns==""
    groups=repmat("series",height(T),1); return;
end
parts=split(columns,"|"); groups=repmat("",height(T),1);
names=string(T.Properties.VariableNames);
for k=1:numel(parts)
    if ~ismember(parts(k),names)
        error("sixgr:csi:MissingFigureGroupColumn", ...
            "Figure group column %s is absent.",parts(k));
    end
    values=string(T.(parts(k)));
    token=parts(k)+"="+values;
    if k==1, groups=token; else, groups=groups+"; "+token; end
end
end
function value=localIf(tf,a,b)
if tf, value=a; else, value=b; end
end
