function contract=executionFlowContract(repoRoot)
%EXECUTIONFLOWCONTRACT Validate the single DL-CSI production/test flow.
%
% The CSI package owns orchestration only. PHY, measurement, MIMO, beam,
% link-adaptation and coded-link behavior remain in their established
% production packages. This function makes those bindings executable and
% fails if an orchestration-local duplicate shadows an authoritative owner.
arguments
    repoRoot (1,1) string = localRepoRoot()
end

role=[ ...
    "configuration";"suite_orchestration";"standard_csirs"; ...
    "high_port_csirs";"occ_cdm";"measurement_state";"csi_feedback"; ...
    "measurement_link_adaptation";"beam_management"; ...
    "coded_pdsch_truth";"artifact_export"];
owner=[ ...
    "sixgr.csi.loadTDocConfig";"sixgr.csi.runTDocSuite"; ...
    "sixgr.phy.refsig.csirs";"sixgr.phy.refsig.HighPortCSIRSMapper"; ...
    "sixgr.phy.refsig.OCCFactory";"sixgr.phy.mimo.CSIMeasurementState"; ...
    "sixgr.mimo.buildCSIFeedback";"sixgr.phy.rsla.MeasurementStateStore"; ...
    "sixgr.phy.beam.BeamManagementStateMachine"; ...
    "sixgr.lls.runPDSCHTransportBlock";"sixgr.csi.ResultWriter"];
relativePath=[ ...
    "+sixgr/+csi/loadTDocConfig.m";"+sixgr/+csi/runTDocSuite.m"; ...
    "+sixgr/+phy/+refsig/csirs.m"; ...
    "+sixgr/+phy/+refsig/HighPortCSIRSMapper.m"; ...
    "+sixgr/+phy/+refsig/OCCFactory.m"; ...
    "+sixgr/+phy/+mimo/CSIMeasurementState.m"; ...
    "+sixgr/+mimo/buildCSIFeedback.m"; ...
    "+sixgr/+phy/+rsla/MeasurementStateStore.m"; ...
    "+sixgr/+phy/+beam/BeamManagementStateMachine.m"; ...
    "+sixgr/+lls/runPDSCHTransportBlock.m"; ...
    "+sixgr/+csi/ResultWriter.m"];
responsibility=[ ...
    "resolve and validate layered YAML"; ...
    "only public CSI TDoc execution entry point"; ...
    "Release-18 CSI-RS rows supported by 5G Toolbox"; ...
    "128/256/512 logical-port streamed waveform mapping"; ...
    "normalized Walsh/DFT OCC matrices and coupling"; ...
    "immutable measured CSI state and age validation"; ...
    "RI/PMI/CQI selection and typed report construction"; ...
    "causal measured-state storage for RSLA consumers"; ...
    "measured P1/P2/P3 and TCI state transitions"; ...
    "production PDSCH/DL-SCH transmitter-receiver truth"; ...
    "atomic provenance-bearing CSI artifact output"];

n=numel(role); exists=false(n,1); canonical=false(n,1);
resolvedPath=strings(n,1);
for k=1:n
    expected=string(fullfile(repoRoot,relativePath(k)));
    exists(k)=isfile(expected);
    resolvedPath(k)=string(which(char(owner(k))));
    canonical(k)=exists(k) && localSamePath(expected,resolvedPath(k));
end
contract=table(role,owner,relativePath,resolvedPath,exists,canonical, ...
    responsibility,repmat("PASS",n,1),'VariableNames', ...
    {'Role','CanonicalOwner','RepositoryPath','ResolvedMATLABPath', ...
    'Exists','CanonicalPathSelected','Responsibility','Status'});

if any(~exists | ~canonical)
    bad=contract(~exists | ~canonical,:);
    error("sixgr:csi:NonCanonicalExecutionFlow", ...
        "CSI execution owner '%s' is missing or shadowed; expected %s, resolved %s.", ...
        bad.CanonicalOwner(1),bad.RepositoryPath(1),bad.ResolvedMATLABPath(1));
end

% These implementations belong to established packages. A copy under
% +sixgr/+csi would fork the architecture and must fail before execution.
forbidden=["csirs.m";"HighPortCSIRSMapper.m";"OCCFactory.m"; ...
    "CSIMeasurementState.m";"buildCSIFeedback.m"; ...
    "MeasurementStateStore.m";"OLLAState.m"; ...
    "BeamManagementStateMachine.m";"PDSCH_Tx.m";"PDSCH_Rx.m"];
for k=1:numel(forbidden)
    candidate=fullfile(repoRoot,"+sixgr","+csi",forbidden(k));
    if isfile(candidate)
        error("sixgr:csi:DuplicateImplementation", ...
            "Duplicate CSI implementation is forbidden at %s.",candidate);
    end
end
end

function tf=localSamePath(a,b)
if strlength(b)==0, tf=false; return; end
a=replace(string(a),"/","\"); b=replace(string(b),"/","\");
tf=strcmpi(char(a),char(b));
end

function root=localRepoRoot()
root=string(fileparts(fileparts(fileparts(mfilename("fullpath")))));
end
