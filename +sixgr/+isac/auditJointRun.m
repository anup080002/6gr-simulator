function report=auditJointRun(runFolder)
%AUDITJOINTRUN Independently audit a completed joint-ISAC evidence folder.

arguments
    runFolder (1,1) string
end
if exist(runFolder,"dir")~=7
    error("sixgr:isac:MissingJointRunFolder","Joint ISAC run folder not found: %s",runFolder);
end
runFolder=string(char(java.io.File(char(runFolder)).getCanonicalPath()));
csvFiles=dir(fullfile(runFolder,"**","*.csv"));
pngFiles=dir(fullfile(runFolder,"**","*.png"));
svgFiles=dir(fullfile(runFolder,"**","*.svg"));
for i=1:numel(csvFiles)
    path=fullfile(csvFiles(i).folder,csvFiles(i).name);
    localRequire(csvFiles(i).bytes>0,"sixgr:isac:EmptyCSV","CSV is empty: "+string(path));
    value=readtable(path,"TextType","string","VariableNamingRule","preserve");
    names=lower(string(value.Properties.VariableNames));
    localRequire(numel(unique(names))==numel(names), ...
        "sixgr:isac:DuplicateCSVColumn","CSV contains duplicate columns: "+string(path));
end

trials=readtable(fullfile(runFolder,"tables","Table03_waveform_trials.csv"), ...
    "TextType","string");
localRequire(height(trials)>0 && numel(unique(trials.TrialId))==height(trials), ...
    "sixgr:isac:InvalidTrialIdentity","Trial IDs must be nonempty and unique.");
target=logical(trials.TargetPresent);
localRequire(all(isfinite(trials.MeasuredRangeM(target))) && ...
    all(isfinite(trials.RangeErrorM(target))), ...
    "sixgr:isac:InvalidRangeEvidence","Target-present rows require finite measured range/error.");
dopplerRequired=target & trials.CoherentSymbols>1;
localRequire(all(isfinite(trials.MeasuredDopplerHz(dopplerRequired))), ...
    "sixgr:isac:InvalidDopplerEvidence", ...
    "Target-present multi-symbol rows require finite measured Doppler.");
angleRequired=logical(trials.AngleMeasurementApplicable);
localRequire(all(isfinite(trials.MeasuredAzimuthDeg(angleRequired))), ...
    "sixgr:isac:InvalidAngleEvidence","Angle-applicable rows require finite azimuth.");
localRequire(all(isfinite(trials.CommunicationEVMRMS) & trials.CommunicationEVMRMS>=0), ...
    "sixgr:isac:InvalidCommunicationEVM","Communication EVM must be finite and nonnegative.");
localRequire(all(trials.UncodedSymbolErrorRate>=0 & trials.UncodedSymbolErrorRate<=1), ...
    "sixgr:isac:InvalidCommunicationSER","Uncoded SER must lie in [0,1].");
localRequire(all(isfinite(trials.PAPRDb) & trials.PAPRDb>=0) && ...
    all(isfinite(trials.PSLRDb) & trials.PSLRDb<=0), ...
    "sixgr:isac:InvalidWaveformMetric","PAPR/PSLR values violate physical bounds.");
localRequire(all(strlength(trials.TransmitWaveformSHA256)==64) && ...
    all(strlength(trials.ReceivedObservationSHA256)==64), ...
    "sixgr:isac:InvalidWaveformHash","Every trial requires transmit/receive SHA-256 hashes.");

patterns=readtable(fullfile(runFolder,"tables","Table06_effective_patterns.csv"), ...
    "TextType","string");
localRequire(numel(unique(patterns.Response))==10 && ...
    numel(unique(patterns.CollisionMaskProfile))==5, ...
    "sixgr:isac:IncompleteCollisionCoverage", ...
    "Effective-pattern evidence must include ten responses and five mask profiles.");
localRequire(all(patterns.RetainedObservations>=0) && ...
    all(patterns.RetainedObservations<=patterns.ConfiguredObservations+patterns.ReplacementObservations), ...
    "sixgr:isac:InvalidEffectivePatternCount","Effective-pattern observation count is invalid.");

tdd=readtable(fullfile(runFolder,"tables","Table08_tdd_patterns.csv"),"TextType","string");
localRequire(numel(unique(tdd.PhaseRelation))==4, ...
    "sixgr:isac:IncompleteTDDPhaseCoverage","Four TDD phase relations are required.");
localRequire(all(abs(tdd.CoherentGainLinear(tdd.PhaseRelation=="continuous")-1)<1e-12) && ...
    all(abs(tdd.CoherentGainLinear(tdd.PhaseRelation=="known_compensated")-1)<1e-12), ...
    "sixgr:isac:InvalidTDDCompensation","Continuous/known-compensated TDD gain must be unity.");

assistance=readtable(fullfile(runFolder,"tables","Table10_assistance.csv"),"TextType","string");
localRequire(all(diff(assistance.SearchOperations)>=0) && ...
    all(assistance.ObservedWrongPeakRate>=0 & assistance.ObservedWrongPeakRate<=1), ...
    "sixgr:isac:InvalidAssistanceEvidence","Assistance cost/probability values are invalid.");
beam=readtable(fullfile(runFolder,"tables","Table09_beam_management.csv"),"TextType","string");
localRequire(all(beam.MedianGainGapDb>=0 & beam.P90GainGapDb>=0) && ...
    all(beam.FallbackRate>=0 & beam.FallbackRate<=1), ...
    "sixgr:isac:InvalidBeamEvidence","Beam gain-gap/fallback values are invalid.");

acceptance=readtable(fullfile(runFolder,"tables","Table17_acceptance.csv"),"TextType","string");
verification=readtable(fullfile(runFolder,"aggregate","artifact_verification.csv"),"TextType","string");
localRequire(all(acceptance.Pass),"sixgr:isac:AcceptanceFailed","One or more acceptance checks failed.");
localRequire(all(verification.Pass),"sixgr:isac:ArtifactVerificationFailed", ...
    "One or more artifact checks failed.");
anchorVisual=sixgr.visual.verifyVisualArtifacts(fullfile(runFolder,"full_phy_anchor"),table());
localRequire(~isempty(anchorVisual) && all(anchorVisual.IntegrityOk), ...
    "sixgr:isac:AnchorVisualIntegrityFailed","Full-PHY anchor visual lineage failed.");
localRequire(isempty(svgFiles),"sixgr:isac:SVGProhibited","SVG output is prohibited.");

checks=["CSV schema/nonempty";"Trial numerical bounds";"Collision coverage"; ...
    "TDD phase policies";"Assistance bounds";"Beam bounds"; ...
    "Semantic acceptance";"Artifact verification";"Anchor visual lineage"; ...
    "PNG-only raster policy"];
details=[string(numel(csvFiles))+" CSV files";string(height(trials))+" unique trials"; ...
    "10 responses, 5 masks";"4 phase relations";string(height(assistance))+" windows"; ...
    string(height(beam))+" information ages";string(height(acceptance))+" checks"; ...
    string(height(verification))+" checks";string(height(anchorVisual))+" anchor images"; ...
    string(numel(pngFiles))+" PNG, 0 SVG"];
report=table(checks,true(numel(checks),1),details, ...
    'VariableNames',{'Check','Pass','Details'});
writetable(report,fullfile(runFolder,"aggregate","scientific_audit.csv"));
end

function localRequire(condition,identifier,message)
if ~condition, error(identifier,"%s",message); end
end
