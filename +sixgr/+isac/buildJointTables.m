function tables = buildJointTables(cfg,plan,trialRows,geometryRows,diagnostics,studies,aggregate)
%BUILDJOINTTABLES Populate the seventeen TDoc table groups from run data.

mode = string(cfg.run.activeMode);
carrier = sixgr.util.structGet(cfg,"carrier.profiles."+string(cfg.carrier.activeProfile),struct());
tables.Table01_assumptions = table( ...
    ["Schema version";"Run mode";"Evidence class";"Carrier profile"; ...
    "Carrier frequency Hz";"Channel bandwidth Hz";"Subcarrier spacing kHz"; ...
    "Resource blocks";"Waveform profiles";"Paired seeds"; ...
    "Controlled channel";"Geometry channel";"Image format"; ...
    "SVG prohibited";"Source DOCX status"], ...
    [string(cfg.schemaVersion);mode;string(cfg.study.evidenceClass); ...
    string(cfg.carrier.activeProfile);string(carrier.frequencyHz); ...
    string(carrier.channelBandwidthHz);string(carrier.subcarrierSpacingKHz); ...
    string(carrier.nSizeGrid);join(localStrings(sixgr.util.structGet(cfg,"run.modes."+mode+".waveformProfiles",[])),"|"); ...
    string(cfg.run.pairedSeeds);string(cfg.channel.controlledBackend); ...
    string(cfg.channel.geometryBackend);string(cfg.output.imageFormat); ...
    string(cfg.output.prohibitSVG);"required_source_unavailable"], ...
    [repmat("resolved_yaml",14,1);"filesystem_source_audit"], ...
    'VariableNames',{'Assumption','Value','Authority'});

if isempty(geometryRows)
    tables.Table02_geometry = table();
else
    [~,uniqueIndex] = unique(geometryRows(:,{'TxX_m','TxY_m','TxZ_m','RxX_m','RxY_m','RxZ_m', ...
        'TargetX_m','TargetY_m','TargetZ_m'}),'rows','stable');
    tables.Table02_geometry = geometryRows(uniqueIndex,:);
end
tables.Table03_waveform_trials = trialRows;
tables.Table04_profile_metrics = aggregate.ProfileMetrics;
tables.Table05_coherency_events = studies.EventSummary;
tables.Table06_effective_patterns = studies.EffectivePatterns;
tables.Table07_coherency_budget = studies.BudgetEvaluation;
tables.Table08_tdd_patterns = studies.TDD;
tables.Table09_beam_management = studies.BeamManagement;
tables.Table10_assistance = studies.Assistance;
tables.Table11_fairness = studies.Fairness;
tables.Table12_waveform_summary = diagnostics.WaveformSummary;
tables.Table13_communication_metrics = aggregate.Communication;
tables.Table14_complexity = aggregate.Complexity;
tables.Table15_w3_absolute_state = diagnostics.W3State;

sourceNames = [ ...
    "R1-26xxxx_Jio_ISAC_Integration_Maastricht_Final_Submission.docx"; ...
    "R1-26xxxx_Jio_ISAC_Integration_Maastricht_Final.docx"; ...
    "Patent_Coherency_Budgeted_Collision_Handling_ISAC.docx"; ...
    "R1-2605133 Summary on ISAC integration_v055_ZTE_Moderator.docx"; ...
    "R1-26xxxx_Discussion_on_CP_OFDM_multi_symbol_sensing_RS_corrected.docx"; ...
    "R1-26xxxx_Discussion_on_CP_OFDM_sensing_RS_frame_anchored_evaluation_6G_ISAC_final.docx"; ...
    "R1-2603665 Discussion on integration aspects for 6G ISAC.docx"; ...
    "R1-2603605 Discussion on aspects of integration of sensing with communication.docx"; ...
    "R1-2603537_or_R1-2503537_sensing_integration_10_8_2.docx"];
tables.Table16_source_availability = table(sourceNames,false(9,1), ...
    repmat("required_source_unavailable_no_values_invented",9,1), ...
    'VariableNames',{'SourceDocument','Present','Status'});

planned = numel(plan);
executed = height(trialRows);
w3 = diagnostics.W3State.CumulativeCPStateQ;
puncturedBundle = sixgr.isac.buildJointWaveform(cfg,"W3",double(cfg.run.masterSeed), ...
    double(cfg.waveform.sensingSymbolIndices(2)));
w3Invariant = isequal(w3,puncturedBundle.CumulativeCPState(:));
phaseReference = abs(0.5+0.5*exp(1i*pi/2))^2;
phaseNumerical = studies.EventPhase.CoherentGainLinear( ...
    studies.EventPhase.PhaseStepDeg == 90 & ...
    studies.EventPhase.FractionBeforeEvent == 0.5);
phasePass = ~isempty(phaseNumerical) && abs(phaseNumerical(1)-phaseReference) < 1e-12;
mono = sixgr.isac.bistaticGeometry([0;0;0],[0;0;0],[10;0;0],[2;0;0],3e9,"trp_monostatic");
monoPass = abs(abs(mono.DopplerHz)-2*2/mono.WavelengthM) < 1e-12;
checks = ["all_planned_trials_executed";"all_W0_W1_W2_W3_profiles_executed"; ...
    "W3_puncture_preserves_absolute_q";"phase_step_gain_matches_analytical"; ...
    "monostatic_doppler_special_case";"paired_seed_fairness"; ...
    "common_waveform_hash_present";"range_estimates_finite"; ...
    "distinct_W0_W2_waveform_identity";"eight_element_angle_measurement_executed"; ...
    "output_raster_policy_png_only";"pre6g_example_waveform_executed"; ...
    "official_TR38901_example_channel_executed"; ...
    "all_collision_responses_waveform_executed"; ...
    "relocation_sequence_reconstruction_executed"; ...
    "receiver_knowledge_contrast_executed"; ...
    "periodic_phase_ghost_matches_analytical_location"; ...
    "interference_and_isi_ici_waveforms_executed"; ...
    "all_configured_tdd_patterns_executed"; ...
    "all_event_classes_executed";"papr_uses_all_configured_seeds"; ...
    "relocation_REs_not_scored_as_communication_data"];
waveformHashes = diagnostics.WaveformSummary;
w0Hash = waveformHashes.WaveformSHA256(waveformHashes.WaveformProfile=="W0");
w2Hash = waveformHashes.WaveformSHA256(waveformHashes.WaveformProfile=="W2");
angleRows = trialRows.ReceiveElements==8 & trialRows.TargetPresent;
j3Rows=trialRows.Stage=="J3_response";
requiredResponses=string(cfg.collisions.responses(:));
relocationNames=["time_relocation","frequency_relocation", ...
    "comb_pattern_selection","recoverable_relocation"];
relocationRows=j3Rows&ismember(trialRows.CollisionResponse,relocationNames);
knowledgeRows=trialRows.Stage=="J3_receiver_knowledge";
expectedKnowledge=["known_cancelled","decoded_reconstructed","residual_data_interference"];
periodicDelta=abs(studies.PeriodicPhase.Summary.ExpectedGhostOffsetNormalized- ...
    studies.PeriodicPhase.Summary.MeasuredGhostOffsetNormalized);
configuredTDD=string(fieldnames(cfg.tdd.patterns));
requiredEvents=["common_phase_step","timing_update","residual_frequency_update", ...
    "port_phase_slope","periodic_two_state_phase"];
modeCfg=cfg.run.modes.(char(cfg.run.activeMode));
pass = [executed == planned;all(ismember(["W0","W1","W2","W3"],unique(trialRows.WaveformProfile))); ...
    w3Invariant;phasePass;monoPass;logical(cfg.run.pairedSeeds); ...
    all(strlength(trialRows.TransmitWaveformSHA256) == 64); ...
    all(isfinite(trialRows.MeasuredRangeM(trialRows.TargetMetricApplicable))); ...
    isscalar(w0Hash)&&isscalar(w2Hash)&&w0Hash~=w2Hash; ...
    any(angleRows)&&all(isfinite(trialRows.MeasuredAzimuthDeg(angleRows))); ...
    lower(string(cfg.output.imageFormat)) == "png" && logical(cfg.output.prohibitSVG); ...
    diagnostics.Pre6GExample.ExecutionBackend=="6g_exploration_library_simulation" && ...
        strlength(diagnostics.Pre6GExample.WaveformSHA256)==64; ...
    diagnostics.TR38901Summary.EvidenceClass=="official_mathworks_example_helper_execution" && ...
        strlength(diagnostics.TR38901Summary.HelperSHA256)==64 && ...
        strlength(diagnostics.TR38901Summary.ReceivedSHA256)==64; ...
    all(ismember(requiredResponses,unique(trialRows.CollisionResponse(j3Rows)))); ...
    any(relocationRows)&&all(trialRows.ReplacementObservations(relocationRows)>0); ...
    all(ismember(expectedKnowledge,unique(trialRows.SharedResourceKnowledge(knowledgeRows)))); ...
    all(periodicDelta<1e-12); ...
    ~isempty(studies.Interference)&&~isempty(studies.ISIICI)&& ...
        all(strlength(studies.Interference.ReceivedWaveformSHA256)==64)&& ...
        all(strlength(studies.ISIICI.ReceivedWaveformSHA256)==64); ...
    all(ismember(configuredTDD,unique(studies.TDD.TDDPattern))); ...
    all(ismember(requiredEvents,unique(studies.EventSummary.EventType))); ...
    all(diagnostics.PAPRCCDF.WaveformSeeds==numel(modeCfg.trialSeeds)); ...
    ~any(trialRows.UncodedDataBlockError(relocationRows))];
details = [sprintf("planned=%d executed=%d",planned,executed); ...
    join(unique(trialRows.WaveformProfile),"|"); ...
    "q vector identical after omitted sensing symbol"; ...
    sprintf("analytical=%.15g numerical=%.15g",phaseReference,phaseNumerical(1)); ...
    sprintf("doppler_hz=%.15g",mono.DopplerHz); ...
    "run.pairedSeeds=true";"64-character SHA-256 for every trial"; ...
    "all measured range values finite";"W0 symbol-varying Gold differs from W2 repeated base"; ...
    sprintf("eight_element_rows=%d",nnz(angleRows));"PNG enabled; SVG prohibited"; ...
    "installed R2026a pre6G waveform APIs; simulation, no USRP claim"; ...
    "official example helper and received waveform hashes recorded"; ...
    join(unique(trialRows.CollisionResponse(j3Rows)),"|"); ...
    sprintf("relocation_rows=%d replacement_observations=%d",nnz(relocationRows), ...
        sum(trialRows.ReplacementObservations(relocationRows))); ...
    join(unique(trialRows.SharedResourceKnowledge(knowledgeRows)),"|"); ...
    sprintf("maximum_normalized_offset_delta=%.3g",max(periodicDelta)); ...
    sprintf("interference_rows=%d isi_ici_rows=%d",height(studies.Interference),height(studies.ISIICI)); ...
    join(unique(studies.TDD.TDDPattern),"|");join(unique(studies.EventSummary.EventType),"|"); ...
    sprintf("waveform_seeds=%d symbols_per_profile=%d",numel(modeCfg.trialSeeds), ...
        max(diagnostics.PAPRCCDF.OFDMSymbolSamples)); ...
    sprintf("relocation_rows=%d uncoded_block_errors=%d",nnz(relocationRows), ...
        nnz(trialRows.UncodedDataBlockError(relocationRows)))];
tables.Table17_acceptance = table(checks,pass,details, ...
    'VariableNames',{'Check','Pass','Details'});
end

function out = localStrings(value)
out = string(value(:));
end
