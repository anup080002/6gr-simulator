function anchor=runFullPHYAnchor(jointCfg)
%RUNFULLPHYANCHOR Execute the production PDSCH-to-sensing receiver anchor.

arguments
    jointCfg (1,1) struct
end
anchorCfg=sixgr.util.structGet(jointCfg,"fullPHYAnchor",struct());
if ~logical(sixgr.util.structGet(anchorCfg,"enabled",false))
    anchor=struct("Enabled",false,"Summary",table());
    return;
end
configPath=string(anchorCfg.configPath);
[llsCfg,provenance]=sixgr.lls.loadConfig(configPath);
sourcePath=string(provenance.ConfigPath);
llsCfg.isac.coherentRepetitions=double(anchorCfg.coherentRepetitions);
phyCfg=sixgr.lls.buildPHYConfig(llsCfg,double(anchorCfg.snrDb));
[linkRow,diagnostic]=sixgr.lls.runPDSCHTransportBlock(llsCfg,phyCfg, ...
    string(provenance.ConfigSHA256),1,1,"CaptureDiagnostic",true);
tx=diagnostic.Tx;
sensing=diagnostic.ISAC;
if ~logical(sensing.EvidenceValid)
    error("sixgr:isac:FullPHYAnchorFailed", ...
        "The production PDSCH sensing anchor did not satisfy its configured target-matching acceptance.");
end
runtime=sensing.RuntimeTable(1,:);
summary=table(true,string(configPath),string(sourcePath), ...
    string(anchorCfg.executionProfile),double(anchorCfg.snrDb), ...
    double(anchorCfg.coherentRepetitions),string(anchorCfg.evidenceClass), ...
    string(runtime.WaveformSource),string(runtime.ChannelSource), ...
    string(runtime.ProcessingSource),logical(runtime.EvidenceValid), ...
    double(runtime.MatchedTargetCount),double(runtime.RangeRMSEM), ...
    double(runtime.AzimuthRMSEDeg),string(sensing.LogicalWaveformSHA256), ...
    string(sensing.PhysicalWaveformSHA256),string(sensing.ReceivedSensingCubeSHA256), ...
    height(sensing.DetectionTable),numel(tx.Waveform),logical(linkRow.CRCError), ...
    double(linkRow.BitErrors),double(linkRow.MeasuredSNRdB),double(linkRow.PostEqSINRdB), ...
    string(sixgr.util.sha256Hex(typecast(double(tx.TransportBlock(:)),"uint8"))), ...
    'VariableNames',{'Enabled','ConfigPath','ResolvedConfigPath','ExecutionProfile', ...
    'SNRDb','CoherentRepetitions','EvidenceClass','WaveformSource','ChannelSource', ...
    'ProcessingSource','EvidenceValid','MatchedTargetCount','RangeRMSEM', ...
    'AzimuthRMSEDeg','LogicalWaveformSHA256','PhysicalWaveformSHA256', ...
    'ReceivedSensingCubeSHA256','DetectionCount','WaveformSamples','CRCError', ...
    'BitErrors','MeasuredSNRDb','PostEqSINRDb','TransportBlockSHA256'});
anchor=struct("Enabled",true,"Summary",summary,"Sensing",sensing, ...
    "LinkRow",linkRow,"Config",llsCfg,"SourcePath",string(sourcePath));
end
