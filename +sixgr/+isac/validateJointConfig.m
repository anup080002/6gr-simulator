function validateJointConfig(cfg)
%VALIDATEJOINTCONFIG Fail closed on the joint 10.8.2/10.8.3 contract.

required = [ ...
    "schemaVersion"; "study.id"; "study.evidenceClass"; ...
    "run.activeMode"; "run.masterSeed"; "run.pairedSeeds"; ...
    "carrier.activeProfile"; "waveform.sensingSymbolIndices"; ...
    "waveform.frequencyComb"; "waveform.frequencyCombOffset"; ...
    "waveform.defaultCoherentSymbols";"waveform.w1RandomizationSubcases"; ...
    "receiver.snrDb"; "receiver.ofdmCyclicPrefixFraction"; ...
    "receiver.maximumSearchDelayOverCP"; "channel.controlledBackend"; ...
    "channel.tr38901Backend.enabled"; ...
    "channel.tr38901Backend.referenceExample.enabled"; ...
    "channel.tr38901Backend.referenceExample.waveformProfile"; ...
    "channel.tr38901Backend.referenceExample.sensingMode"; ...
    "channel.propagationSpeedMps"; "scene.activeTarget"; ...
    "scene.nodes.trp1OrientationDeg"; "scene.nodes.trp2OrientationDeg"; ...
    "antenna.angleEstimation.minimumDeg"; ...
    "antenna.angleEstimation.maximumDeg"; "antenna.angleEstimation.stepDeg"; ...
    "resourcePatterns.activePattern"; "collisions.responses"; ...
    "collisions.maskProfiles";"collisions.responseProperties"; ...
    "tdd.phaseRelations";"assistance.searchFFTLength"; ...
    "assistance.priorDopplerErrorStdCyclesPerSlot"; ...
    "beamManagement.algorithm";"beamManagement.arrayElements"; ...
    "fullPHYAnchor.enabled";"fullPHYAnchor.configPath"; ...
    "fullPHYAnchor.executionProfile";"fullPHYAnchor.snrDb"; ...
    "fullPHYAnchor.coherentRepetitions";"fullPHYAnchor.evidenceClass"; ...
    "fullPHYAnchor.sharedResourceAllocation.policy"; ...
    "fullPHYAnchor.sharedResourceAllocation.startPRB"; ...
    "fullPHYAnchor.sharedResourceAllocation.numberPRB"; ...
    "fullPHYAnchor.sharedResourceAllocation.symbols"; ...
    "interferenceStudy.enabled"; ...
    "interferenceStudy.intercellRelativePowerDb"; ...
    "interferenceStudy.asynchronousDelayOverCP"; ...
    "interferenceStudy.asynchronousFrequencyOffsetHz"; ...
    "interferenceStudy.selfInterferenceResidualDb"; ...
    "interferenceStudy.isiIciWaveformProfiles"; ...
    "rangeDopplerEvidence.delayOverCP"; ...
    "rangeDopplerEvidence.delayClasses"; ...
    "rangeDopplerEvidence.delayHypotheses"; ...
    "rangeDopplerEvidence.dopplerHypotheses"; ...
    "coherencyBudget.measurementProfiles"; "metrics.requested"; ...
    "metrics.publicationPFA"; "metrics.minimumExpectedFalseAlarmsForQualification"; ...
    "detection.probabilityFalseAlarm"; "detection.delayToleranceBins"; ...
    "validation.stage1.seed"; ...
    "validation.stage1.cpSafe.delayOverCP"; ...
    "validation.stage1.cpSafe.integerEVMTolerance"; ...
    "validation.stage1.cpSafe.fractionalEVMTolerance"; ...
    "validation.stage1.linearConvolution.delayOverCP"; ...
    "validation.stage1.offGrid.delayFractions"; ...
    "validation.stage1.offGrid.dopplerFractions"; ...
    "validation.stage1.offGrid.maximumRangeErrorBins"; ...
    "validation.stage1.offGrid.maximumDopplerErrorHz"; ...
    "validation.stage1.puncture.ratioPercent"; ...
    "validation.comparative.activeClass"; ...
    "validation.comparative.receivers"; ...
    "validation.comparative.scenarioClasses"; ...
    "validation.comparative.delayOverCP"; ...
    "validation.intrinsic.activeClass"; ...
    "validation.intrinsic.spectralOversampledNfft"; ...
    "validation.intrinsic.ambiguity.maximumDelaySamples"; ...
    "validation.stress.activeClass"; ...
    "validation.stress.intercellRelativePowerDb"; ...
    "validation.stress.selfInterferenceResidualDb"; ...
    "validation.stress.punctureRatesPercent"; ...
    "validation.stress.puncturePatterns"; ...
    "validation.stress.relocationResidualPhaseDeg"; ...
    "output.saveFIG";"output.savePDF"; ...
    "pre6gExampleAdapter.enabled"; "pre6gExampleAdapter.hardwareEnabled"; ...
    "pre6gExampleAdapter.nSizeGrid"; ...
    "pre6gExampleAdapter.subcarrierSpacingKHz"; ...
    "pre6gExampleAdapter.dmrs.subcarrierLocations"; ...
    "pre6gExampleAdapter.dmrs.symbolLocations"; ...
    "output.root"; "output.imageFormat"; "output.prohibitSVG"; ...
    "output.imageResolutionDPI";"output.imageSizePixels"; ...
    "output.saveCSV"; "output.saveMAT"; "output.savePNG"];
for i = 1:numel(required)
    if isempty(sixgr.util.structGet(cfg,required(i),[]))
        error("sixgr:isac:MissingJointConfiguration", ...
            "Resolved joint ISAC YAML is missing %s.",required(i));
    end
end
if string(cfg.schemaVersion) ~= "sixgr.isac.joint.v1"
    error("sixgr:isac:UnsupportedJointSchema", ...
        "Expected schemaVersion sixgr.isac.joint.v1, received %s.", ...
        string(cfg.schemaVersion));
end
mode = lower(string(cfg.run.activeMode));
if ~ismember(mode,["quick","tdoc","full"])
    error("sixgr:isac:InvalidRunMode","Unsupported joint ISAC mode %s.",mode);
end
modeCfg = sixgr.util.structGet(cfg,"run.modes."+mode,[]);
if ~(isstruct(modeCfg) && isscalar(modeCfg))
    error("sixgr:isac:MissingRunModeConfiguration", ...
        "Missing run.modes.%s configuration.",mode);
end
modeRequired = ["trialSeeds","waveformProfiles","delayOverCP", ...
    "normalizedDoppler","coherentSymbols","collisionRatiosPercent", ...
    "tddPatterns","sensingModes","noTargetTrials","targetTrials"];
for i = 1:numel(modeRequired)
    if isempty(sixgr.util.structGet(modeCfg,modeRequired(i),[]))
        error("sixgr:isac:MissingRunModeConfiguration", ...
            "Missing run.modes.%s.%s.",mode,modeRequired(i));
    end
end

profileName = string(cfg.carrier.activeProfile);
profile = sixgr.util.structGet(cfg,"carrier.profiles."+profileName,[]);
if ~(isstruct(profile) && isscalar(profile))
    error("sixgr:isac:MissingCarrierProfile", ...
        "carrier.activeProfile %s is not defined.",profileName);
end
localPositive(profile,"frequencyHz");
localPositive(profile,"channelBandwidthHz");
localPositive(profile,"subcarrierSpacingKHz");
localInteger(profile,"nSizeGrid",1,275);
localInteger(profile,"nStartGrid",0,2199);
localInteger(profile,"nCellID",0,1007);
if lower(string(profile.cyclicPrefix)) ~= "normal"
    error("sixgr:isac:UnsupportedCyclicPrefix", ...
        "The joint W0-W3 campaign currently requires normal CP.");
end
shared=cfg.fullPHYAnchor.sharedResourceAllocation;
if lower(string(shared.policy))~="sensing_restricted_to_pdsch_allocation"
    error("sixgr:isac:InvalidSharedPDSCHPolicy", ...
        "The 10.8.3 communication gate requires sensing_restricted_to_pdsch_allocation.");
end
sharedStart=localInteger(shared,"startPRB",0,double(profile.nSizeGrid)-1);
sharedCount=localInteger(shared,"numberPRB",1,double(profile.nSizeGrid));
if sharedStart+sharedCount>double(profile.nSizeGrid)
    error("sixgr:isac:InvalidSharedPDSCHAllocation", ...
        "The shared PDSCH PRB allocation exceeds the active carrier grid.");
end
sharedSymbols=double(shared.symbols(:).');
if numel(sharedSymbols)~=2 || any(~isfinite(sharedSymbols)) ...
        || sharedSymbols(1)~=floor(sharedSymbols(1)) ...
        || sharedSymbols(2)~=floor(sharedSymbols(2)) ...
        || sharedSymbols(1)<0 || sharedSymbols(2)<1 ...
        || sum(sharedSymbols)>14
    error("sixgr:isac:InvalidSharedPDSCHSymbols", ...
        "fullPHYAnchor.sharedResourceAllocation.symbols must be [start length] inside one slot.");
end

waveformProfiles = localStrings(modeCfg.waveformProfiles);
if ~all(ismember(waveformProfiles,["W0","W1","W2","W3"]))
    error("sixgr:isac:InvalidWaveformProfile", ...
        "Run-mode waveform profiles must be selected from W0-W3.");
end
for id = ["W0","W1","W2","W3"]
    if ~isstruct(sixgr.util.structGet(cfg,"waveform.profiles."+id,[]))
        error("sixgr:isac:MissingWaveformProfile","Missing waveform profile %s.",id);
    end
end
symbols = double(cfg.waveform.sensingSymbolIndices(:));
if isempty(symbols) || any(symbols ~= floor(symbols)) || any(symbols < 0 | symbols > 13)
    error("sixgr:isac:InvalidSensingSymbols", ...
        "waveform.sensingSymbolIndices must contain unique zero-based symbols in [0,13].");
end
if numel(unique(symbols)) ~= numel(symbols)
    error("sixgr:isac:InvalidSensingSymbols", ...
        "waveform.sensingSymbolIndices must not contain duplicates.");
end
comb = localInteger(cfg.waveform,"frequencyComb",1,64);
offset = localInteger(cfg.waveform,"frequencyCombOffset",0,comb-1);
if offset >= comb
    error("sixgr:isac:InvalidFrequencyComb","Comb offset must be less than comb size.");
end
coherent=double(modeCfg.coherentSymbols(:));
if any(~isfinite(coherent)|coherent<1|coherent~=floor(coherent))
    error("sixgr:isac:InvalidCoherentSymbolSweep", ...
        "run.modes.%s.coherentSymbols must contain positive integers.",mode);
end
if ~ismember(double(cfg.waveform.defaultCoherentSymbols),coherent)
    error("sixgr:isac:DefaultCoherentLengthOutsideMode", ...
        "The default coherent-symbol count must be present in the active-mode sweep.");
end
variants=localStrings(cfg.waveform.w1RandomizationSubcases);
if ~all(ismember(["per_occasion","reset_aligned_interval"],variants))
    error("sixgr:isac:MissingW1RandomizationVariant", ...
        "W1 must configure both per_occasion and reset_aligned_interval variants.");
end
maskProfiles=localStrings(cfg.collisions.maskProfiles);
allowedMasks=["random_isolated","contiguous_time","contiguous_frequency", ...
    "rectangular_tf","periodic_rs","tdd_driven_missing_occasions"];
if ~all(ismember(maskProfiles,allowedMasks))
    error("sixgr:isac:InvalidCollisionMaskProfile", ...
        "Unsupported collision mask profile configured.");
end
relations=localStrings(cfg.tdd.phaseRelations);
if ~all(ismember(["continuous","bounded_30deg","known_compensated","unknown_reset"],relations))
    error("sixgr:isac:MissingTDDPhaseRelation", ...
        "All four across-gap TDD phase relations must be configured.");
end
responses=localStrings(cfg.collisions.responses);
for response=responses.'
    properties=sixgr.util.structGet(cfg,"collisions.responseProperties."+response,[]);
    if ~(isstruct(properties)&&isscalar(properties)&&isfield(properties,"relationClass"))
        error("sixgr:isac:MissingCollisionResponseProperties", ...
            "Collision response %s requires explicit relation/residual properties.",response);
    end
end

if ~logical(cfg.run.pairedSeeds)
    error("sixgr:isac:UnpairedComparisonRejected", ...
        "Joint profile comparisons require run.pairedSeeds=true.");
end
fairnessFields = ["equalOccupiedRECount","equalTotalSensingEnergy", ...
    "equalOccupiedBandwidth","equalObservationTime","equalAntennaPorts", ...
    "equalTargetChannelRealization","equalReceiverKnowledge"];
for i = 1:numel(fairnessFields)
    value = sixgr.util.structGet(cfg.fairness,fairnessFields(i),[]);
    if ~(islogical(value) && isscalar(value) && value)
        error("sixgr:isac:FairnessContractViolation", ...
            "fairness.%s must be true.",fairnessFields(i));
    end
end
if lower(string(cfg.output.imageFormat)) ~= "png" || ...
        ~logical(cfg.output.prohibitSVG) || ~logical(cfg.output.savePNG)
    error("sixgr:isac:InvalidJointRasterPolicy", ...
        "Joint ISAC evidence must use PNG and prohibit SVG.");
end
if ~logical(cfg.output.saveCSV) || ~logical(cfg.output.saveMAT)
    error("sixgr:isac:IncompleteJointOutputContract", ...
        "Joint ISAC requires both CSV and MAT source evidence.");
end
if logical(cfg.channel.tr38901Backend.enabled) && ...
        ~logical(cfg.channel.tr38901Backend.referenceExample.enabled)
    error("sixgr:isac:TR38901ReferenceEvidenceDisabled", ...
        "An enabled TR 38.901 backend requires its reference example execution.");
end

delays = double(modeCfg.delayOverCP(:));
if any(~isfinite(delays) | delays <= 0)
    error("sixgr:isac:InvalidDelaySweep","delayOverCP must be finite and positive.");
end
doppler = double(modeCfg.normalizedDoppler(:));
if any(~isfinite(doppler) | doppler < 0)
    error("sixgr:isac:InvalidDopplerSweep", ...
        "normalizedDoppler must be finite and nonnegative.");
end
collision = double(modeCfg.collisionRatiosPercent(:));
if any(~isfinite(collision) | collision < 0 | collision > 100)
    error("sixgr:isac:InvalidCollisionSweep", ...
        "collisionRatiosPercent must lie in [0,100].");
end
pfa = double(cfg.detection.probabilityFalseAlarm);
if ~(isscalar(pfa) && isfinite(pfa) && pfa > 0 && pfa < 1)
    error("sixgr:isac:InvalidDetectionPFA", ...
        "detection.probabilityFalseAlarm must lie strictly in (0,1).");
end
localInteger(cfg.detection,"delayToleranceBins",0,1024);
localInteger(cfg.validation.stage1,"seed",0,2^53);
localPositive(cfg.validation.stage1.cpSafe,"integerEVMTolerance");
localPositive(cfg.validation.stage1.cpSafe,"fractionalEVMTolerance");
cpSafeDelays=double(cfg.validation.stage1.cpSafe.delayOverCP(:));
if any(~isfinite(cpSafeDelays)|cpSafeDelays<0|cpSafeDelays>=1)
    error("sixgr:isac:InvalidCPSafeSweep", ...
        "validation.stage1.cpSafe.delayOverCP must lie in [0,1).");
end
linearDelays=double(cfg.validation.stage1.linearConvolution.delayOverCP(:));
requiredLinear=[.25;.5;.9;1;1.1;1.25;1.5;2;3];
if ~all(ismember(requiredLinear,linearDelays))
    error("sixgr:isac:IncompleteLinearDelaySweep", ...
        "Stage-1 linear-convolution sweep is missing a mandated delay/CP point.");
end
for path=["delayFractions","dopplerFractions"]
    rawValues=cfg.validation.stage1.offGrid.(path);
    values=double(rawValues(:));
    if numel(values)<3||any(~isfinite(values)|values<=0|values>=.5)
        error("sixgr:isac:InvalidOffGridFractions", ...
            "validation.stage1.offGrid.%s requires at least three fractions in (0,0.5).",path);
    end
end
localPositive(cfg.validation.stage1.offGrid,"maximumRangeErrorBins");
localPositive(cfg.validation.stage1.offGrid,"maximumDopplerErrorHz");
punctureRatio=double(cfg.validation.stage1.puncture.ratioPercent);
if ~(isscalar(punctureRatio)&&isfinite(punctureRatio)&&punctureRatio>0&&punctureRatio<100)
    error("sixgr:isac:InvalidStage1PunctureRatio", ...
        "validation.stage1.puncture.ratioPercent must lie in (0,100).");
end
cpFraction=double(cfg.receiver.ofdmCyclicPrefixFraction);
if ~(isscalar(cpFraction)&&isfinite(cpFraction)&&cpFraction>=0&&cpFraction<=1)
    error("sixgr:isac:InvalidOFDMCyclicPrefixFraction", ...
        "receiver.ofdmCyclicPrefixFraction must lie in [0,1].");
end
localPositive(cfg.receiver,"maximumSearchDelayOverCP");
comparisonClass=lower(string(cfg.validation.comparative.activeClass));
if ~ismember(comparisonClass,["screening","publication"])
    error("sixgr:isac:InvalidComparativeClass", ...
        "validation.comparative.activeClass must be screening or publication.");
end
comparison=cfg.validation.comparative.(comparisonClass);
localInteger(comparison,"h0TrialsPerReceiver",1,1e9);
localInteger(comparison,"targetTrialsPerOperatingPoint",1,1e9);
scenarioClasses=localStrings(cfg.validation.comparative.scenarioClasses);
if ~all(ismember(["single_target_off_grid","two_target_clutter"],scenarioClasses))
    error("sixgr:isac:IncompleteComparativeScenarioClasses", ...
        "Comparative execution must include single-target and two-target/clutter scenarios.");
end
comparisonPFA=double(comparison.probabilityFalseAlarm);
if ~(isscalar(comparisonPFA)&&isfinite(comparisonPFA)&&comparisonPFA>0&&comparisonPFA<1)
    error("sixgr:isac:InvalidComparativePFA", ...
        "Comparative probabilityFalseAlarm must lie in (0,1).");
end
if comparisonClass=="publication" && ...
        (comparison.h0TrialsPerReceiver<100000 || ...
        comparison.targetTrialsPerOperatingPoint<5000 || comparisonPFA~=1e-3)
    error("sixgr:isac:WeakenedPublicationCounts", ...
        "Publication comparison requires PFA=1e-3, >=100000 H0 and >=5000 H1 trials per point.");
end
intrinsicClass=lower(string(cfg.validation.intrinsic.activeClass));
if ~ismember(intrinsicClass,["screening","publication"])
    error("sixgr:isac:InvalidIntrinsicClass", ...
        "validation.intrinsic.activeClass must be screening or publication.");
end
intrinsic=cfg.validation.intrinsic.(intrinsicClass);
localInteger(intrinsic,"paprOFDMSymbolsPerProfile",1,1e8);
localInteger(intrinsic,"crossCorrelationPairsPerClass",1,1e8);
localInteger(intrinsic,"ambiguityDelayBins",3,4097);
localInteger(intrinsic,"ambiguityDopplerBins",3,4097);
spectralNfft=localInteger(cfg.validation.intrinsic,"spectralOversampledNfft",128,1048576);
if spectralNfft<2^(nextpow2(double(profile.nSizeGrid)*12))
    error("sixgr:isac:SpectralNfftTooSmall", ...
        "validation.intrinsic.spectralOversampledNfft cannot contain the occupied grid.");
end
stressClass=lower(string(cfg.validation.stress.activeClass));
if ~ismember(stressClass,["screening","publication"])
    error("sixgr:isac:InvalidStressClass", ...
        "validation.stress.activeClass must be screening or publication.");
end
stress=cfg.validation.stress.(stressClass);
stressPFA=double(stress.probabilityFalseAlarm);
if ~(isscalar(stressPFA)&&isfinite(stressPFA)&&stressPFA>0&&stressPFA<1)
    error("sixgr:isac:InvalidStressPFA", ...
        "validation.stress.%s.probabilityFalseAlarm must lie in (0,1).",stressClass);
end
localInteger(stress,"h0TrialsPerReceiver",1,1e9);
localInteger(stress,"targetTrialsPerPoint",1,1e9);
if stressClass=="screening"
    localInteger(stress,"pdschTransportBlocksPerPoint",1,10000);
else
    localInteger(stress,"pdschMinimumBlockErrors",100,1e9);
    localInteger(stress,"pdschMaximumTransportBlocks",10000,1e9);
    if stress.h0TrialsPerReceiver<100000||stress.targetTrialsPerPoint<5000
        error("sixgr:isac:WeakenedStressPublicationCounts", ...
            "Publication stress requires >=100000 H0 and >=5000 H1 trials per point.");
    end
    if abs(stressPFA-double(cfg.metrics.publicationPFA))>eps
        error("sixgr:isac:StressPublicationPFAMismatch", ...
            "Publication stress PFA must equal metrics.publicationPFA.");
    end
end
localInteger(cfg.validation.stress,"complexityRepetitions",3,10000);
stressPatterns=localStrings(cfg.validation.stress.puncturePatterns);
if ~all(ismember(stressPatterns,allowedMasks)) || ...
        ~all(ismember(["random_isolated","contiguous_time", ...
        "tdd_driven_missing_occasions"],stressPatterns))
    error("sixgr:isac:IncompleteStressPunctureProfiles", ...
        "Stress puncturing must include random, contiguous-time and TDD-driven missing occasions.");
end
publicationPFA = double(cfg.metrics.publicationPFA);
if ~(isscalar(publicationPFA) && isfinite(publicationPFA) && ...
        publicationPFA > 0 && publicationPFA < 1)
    error("sixgr:isac:InvalidPublicationPFA", ...
        "metrics.publicationPFA must lie strictly in (0,1).");
end
if abs(pfa-publicationPFA)>eps(max(abs([pfa publicationPFA])))
    error("sixgr:isac:DetectionPublicationPFAMismatch", ...
        "detection.probabilityFalseAlarm must equal metrics.publicationPFA for a publication-targeted campaign.");
end
localInteger(cfg.metrics,"minimumExpectedFalseAlarmsForQualification",1,1000);
localInteger(cfg.assistance,"searchFFTLength",16,1048576);
localInteger(cfg.beamManagement,"arrayElements",2,4096);
localInteger(cfg.fullPHYAnchor,"coherentRepetitions",1,4096);
localPositive(cfg.output,"imageResolutionDPI");
imageSize=double(cfg.output.imageSizePixels(:));
if numel(imageSize)~=2||any(~isfinite(imageSize)|imageSize<320|imageSize~=floor(imageSize))
    error("sixgr:isac:InvalidImageSize", ...
        "output.imageSizePixels must contain two integer pixel dimensions >=320.");
end
if ~logical(cfg.fullPHYAnchor.enabled)||string(cfg.fullPHYAnchor.evidenceClass)~= ...
        "production_pdsch_waveform_truth"
    error("sixgr:isac:InvalidFullPHYAnchor", ...
        "The joint campaign requires the production PDSCH waveform truth anchor.");
end
end

function stringsOut = localStrings(value)
if iscell(value)
    stringsOut = string(value(:));
else
    stringsOut = string(value(:));
end
stringsOut = strtrim(stringsOut);
end

function value = localPositive(s,path)
value = sixgr.util.structGet(s,path,[]);
if ~(isnumeric(value) && isscalar(value) && isfinite(double(value)) && value > 0)
    error("sixgr:isac:InvalidJointConfiguration", ...
        "%s must be a finite positive scalar.",path);
end
end

function value = localInteger(s,path,minimum,maximum)
value = sixgr.util.structGet(s,path,[]);
if ~(isnumeric(value) && isscalar(value) && isfinite(double(value)) && ...
        value == floor(value) && value >= minimum && value <= maximum)
    error("sixgr:isac:InvalidJointConfiguration", ...
        "%s must be an integer in [%g,%g].",path,minimum,maximum);
end
value = double(value);
end
