classdef ChannelApplicationContract
    %CHANNELAPPLICATIONCONTRACT Exact sample-domain link transformation.
    methods (Static)
        function [output,metadata] = apply(input,link)
            required = ["LinkID","GainLinear","ImpulseResponse", ...
                "DelaySamples","FrequencyOffsetHz","SampleRateHz"];
            for name = required
                if ~isfield(link,char(name))
                    error("sixgr:integration:HiddenNormalization", ...
                        "Channel link is missing explicit field %s.",name);
                end
            end
            if isfield(link,"Normalize") && logical(link.Normalize)
                error("sixgr:integration:HiddenNormalization", ...
                    "Per-link channel normalization is prohibited.");
            end
            impulse = complex(double(link.ImpulseResponse(:)));
            if isempty(impulse) || any(~isfinite(impulse))
                error("sixgr:integration:HiddenNormalization", ...
                    "Channel impulse response must be finite and nonempty.");
            end
            delay = double(link.DelaySamples);
            if delay < 0 || delay ~= fix(delay)
                error("sixgr:integration:HiddenNormalization", ...
                    "Channel delay must be an explicit nonnegative sample count.");
            end
            output = filter(impulse,1,complex(double(input)));
            if delay > 0
                output = [complex(zeros(delay,size(output,2)));output];
                output = output(1:size(input,1),:);
            end
            index = (0:size(output,1)-1).';
            rotation = exp(1j*2*pi*double(link.FrequencyOffsetHz)* ...
                index/double(link.SampleRateHz));
            output = output .* rotation * double(link.GainLinear);
            metadata = struct("LinkID",string(link.LinkID), ...
                "InputSHA256",sixgr.integration.IntegrationHash.data( ...
                localComplexPayload(input)), ...
                "OutputSHA256",sixgr.integration.IntegrationHash.data( ...
                localComplexPayload(output)), ...
                "GainLinear",double(link.GainLinear), ...
                "DelaySamples",delay, ...
                "FrequencyOffsetHz",double(link.FrequencyOffsetHz), ...
                "ImpulseResponseSHA256", ...
                sixgr.integration.IntegrationHash.data( ...
                localComplexPayload(impulse)), ...
                "Normalization","none");
        end
    end
end

function value = localComplexPayload(input)
value = struct("Real",real(double(input(:))).', ...
    "Imag",imag(double(input(:))).',"Size",size(input));
end
