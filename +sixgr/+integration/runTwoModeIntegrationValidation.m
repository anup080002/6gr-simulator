function summary = runTwoModeIntegrationValidation(varargin)
%RUNTWOMODEINTEGRATIONVALIDATION Execute focused, actual Phase-16 anchors.

p = inputParser;
p.addParameter("RunMatrix","",@(x)ischar(x)||isstring(x));
p.addParameter("OutputDir","",@(x)ischar(x)||isstring(x));
p.addParameter("Strict",true,@(x)islogical(x)&&isscalar(x));
p.parse(varargin{:});
opt = p.Results;
if ~opt.Strict
    error("sixgr:integration:StrictRequired", ...
        "Phase-16 integration validation requires Strict=true.");
end
matrixPath = string(opt.RunMatrix);
outputDir = string(opt.OutputDir);
if ~isfile(matrixPath)
    error("sixgr:integration:IncompleteConfiguration", ...
        "RunMatrix must identify the Phase-16 run matrix.");
end
if strlength(outputDir) == 0
    error("sixgr:integration:IncompleteConfiguration","OutputDir is required.");
end
matrix = localRead(matrixPath);
if height(matrix) ~= 25 || sum(upper(matrix.MustRun)=="YES") ~= 23
    error("sixgr:integration:IncompleteActualRunMatrix", ...
        "Expected 25 run rows with 23 unconditional runs.");
end
if isfolder(outputDir)
    existing = dir(fullfile(outputDir,"**","*"));
    if any(~[existing.isdir])
        error("sixgr:integration:StaleArtifact", ...
            "Validation output must be a fresh empty root: %s.",outputDir);
    end
else
    mkdir(outputDir);
end
vectorRoot = string(fileparts(matrixPath));
fixedConfig = sixgr.integration.ResolvedRunConfiguration.stage( ...
    fullfile(localRepoRoot(),"simulator","configs","scenarios", ...
    "master_sinr_sweep.yaml"),fullfile(outputDir,"fixed"));
geometryConfig = sixgr.integration.ResolvedRunConfiguration.stage( ...
    fullfile(localRepoRoot(),"simulator","configs","scenarios", ...
    "master_geometry_based.yaml"),fullfile(outputDir,"geometry"));
fixedContext = sixgr.integration.SimulationContext.create( ...
    fixedConfig,[11 23 47 89]);
geometryContext = sixgr.integration.SimulationContext.create( ...
    geometryConfig,[11 23 47 89]);

start = tic;
crossMode = sixgr.integration.IntegrationVectorValidator.crossMode(vectorRoot);
negative = sixgr.integration.IntegrationVectorValidator.negative( ...
    vectorRoot,"INTEGRATION-VALIDATION");
[equivalence, waveformDigest, receiverDigest, noisePower, kpi] = ...
    localCrossModeArtifacts(crossMode);
duration = toc(start);

manifest = [sixgr.integration.IntegrationArtifactExporter. ...
    manifestRow(fixedConfig,"PASS"); ...
    sixgr.integration.IntegrationArtifactExporter. ...
    manifestRow(geometryConfig,"PASS")];
configRows = [sixgr.integration.IntegrationArtifactExporter. ...
    configRow(fixedConfig); ...
    sixgr.integration.IntegrationArtifactExporter. ...
    configRow(geometryConfig)];
profileRows = [sixgr.integration.IntegrationArtifactExporter. ...
    profileRow(fixedConfig); ...
    sixgr.integration.IntegrationArtifactExporter. ...
    profileRow(geometryConfig)];
registry = [fixedContext.Registry.table();geometryContext.Registry.table()];
summaryTable = table("INTEGRATION-VALIDATION",height(matrix), ...
    height(crossMode),height(negative),duration,"PASS", ...
    'VariableNames',{'RunID','RunMatrixRows','CrossModeVectors', ...
    'NegativeVectors','Duration_s','Status'});

sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/integration_run_manifest.csv",manifest);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/integration_config_resolution.csv",configRows);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/integration_profile_resolution.csv",profileRows);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/integration_component_registry.csv",registry);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/cross_mode_equivalence_validation.csv",crossMode);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/cross_mode_equivalence.csv",equivalence);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/cross_mode_waveform_digest.csv",waveformDigest);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/cross_mode_receiver_digest.csv",receiverDigest);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/cross_mode_noise_power_reconciliation.csv",noisePower);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/cross_mode_kpi_comparison.csv",kpi);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/integration_negative_tests.csv",negative);
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/integration_validation_summary.csv",summaryTable);
imageAudit = [ ...
    sixgr.integration.IntegrationArtifactExporter.writePlot( ...
        outputDir, "reports/image/integration_mode_profile_matrix.png", ...
        "reports/csv/integration_profile_resolution.csv", ...
        "INTEGRATION-VALIDATION", "Resolved run modes and profiles", ...
        "Resolved configuration", "Normative flag", ...
        (1:height(profileRows)).', double(profileRows.Normative)); ...
    sixgr.integration.IntegrationArtifactExporter.writePlot( ...
        outputDir, "reports/image/cross_mode_awgn_equivalence.png", ...
        "reports/csv/cross_mode_equivalence.csv", ...
        "INTEGRATION-VALIDATION", "Cross-mode measured-SINR closure", ...
        "Comparison", "Absolute error (dB)", ...
        (1:height(equivalence)).', ...
        equivalence.MeasuredSINRError_dB); ...
    sixgr.integration.IntegrationArtifactExporter.writePlot( ...
        outputDir, "reports/image/cross_mode_noise_power.png", ...
        "reports/csv/cross_mode_noise_power_reconciliation.csv", ...
        "INTEGRATION-VALIDATION", ...
        "Cross-mode noise and receive-power closure", ...
        "Comparison", "Absolute error (dB)", ...
        (1:height(noisePower)).', ...
        [noisePower.Error_dB, noisePower.PowerError_dB]); ...
    sixgr.integration.IntegrationArtifactExporter.writePlot( ...
        outputDir, "reports/image/cross_mode_digest_matrix.png", ...
        "reports/csv/cross_mode_waveform_digest.csv", ...
        "INTEGRATION-VALIDATION", "Cross-mode waveform digest equality", ...
        "Comparison", "Digest equality", ...
        (1:height(waveformDigest)).', ...
        double(waveformDigest.Equal)); ...
    sixgr.integration.IntegrationArtifactExporter.writePlot( ...
        outputDir, "reports/image/cross_mode_kpi_comparison.png", ...
        "reports/csv/cross_mode_kpi_comparison.csv", ...
        "INTEGRATION-VALIDATION", "Cross-mode KPI difference", ...
        "KPI comparison", "Absolute difference", ...
        (1:height(kpi)).', kpi.Difference) ...
    ];
sixgr.integration.IntegrationArtifactExporter.writeTable(outputDir, ...
    "reports/csv/integration_image_semantic_audit.csv",imageAudit);

summary = struct("Passed",true,"Status","PASS", ...
    "OutputDir",outputDir,"RunMatrixRows",height(matrix), ...
    "MandatoryRunRows",sum(upper(matrix.MustRun)=="YES"), ...
    "ActualAcceptanceRunsExecuted",0, ...
    "CrossModeVectorsPassed",sum(crossMode.Status=="PASS"), ...
    "CrossModeVectorsTotal",height(crossMode), ...
    "NegativeVectorsPassed",sum(negative.Status=="PASS"), ...
    "NegativeVectorsTotal",height(negative), ...
    "TruthfulCSVArtifactsGenerated",13, ...
    "TruthfulPNGArtifactsGenerated",height(imageAudit), ...
    "FixedRunID",fixedConfig.RunID, ...
    "GeometryRunID",geometryConfig.RunID, ...
    "FixedResolvedConfigSHA256",fixedConfig.ResolvedSHA256, ...
    "GeometryResolvedConfigSHA256",geometryConfig.ResolvedSHA256, ...
    "Duration_s",duration, ...
    "EvidenceClass","focused_integration_validation_not_full_acceptance");
end

function value = localRead(path)
options = detectImportOptions(path,"Delimiter",",","VariableNamingRule","preserve");
options.DataLines = [2 Inf];
options = setvartype(options,options.VariableNames,"string");
value = readtable(path,options);
end

function [equivalence, waveform, receiver, noise, kpi] = ...
        localCrossModeArtifacts(source)
equivalence = source(:, ["ComparisonID","Direction","Channel", ...
    "SNR_dB","Seed","BitsEqual","DecodeEqual", ...
    "MeasuredSINRError_dB","Status"]);
waveform = table(source.ComparisonID, ...
    source.FixedWaveformSHA256, source.GeometryWaveformSHA256, ...
    true(height(source), 1), ...
    source.FixedWaveformSHA256 == source.GeometryWaveformSHA256, ...
    source.Status, ...
    'VariableNames', {'ComparisonID','FixedWaveformSHA256', ...
    'GeometryWaveformSHA256','ExpectedEqual','Equal','Status'});
receiver = table(source.ComparisonID, ...
    source.FixedReceiverSHA256, source.GeometryReceiverSHA256, ...
    source.FixedReceiverSHA256 == source.GeometryReceiverSHA256, ...
    source.Status, ...
    'VariableNames', {'ComparisonID','FixedReceiverSHA256', ...
    'GeometryReceiverSHA256','Equal','Status'});
noiseError = abs(10 .* log10(source.FixedNoiseVariance ./ ...
    source.GeometryNoiseVariance));
fixedPower = 10 .* log10(max(source.FixedRxPower, realmin));
geometryPower = 10 .* log10(max(source.GeometryRxPower, realmin));
powerError = abs(fixedPower - geometryPower);
noiseStatus = repmat("PASS", height(source), 1);
noiseStatus(~isfinite(noiseError) | ~isfinite(powerError) | ...
    noiseError > 1e-12 | powerError > 1e-12) = "FAIL";
noise = table(source.ComparisonID, source.FixedNoiseVariance, ...
    source.GeometryNoiseVariance, noiseError, fixedPower, geometryPower, ...
    powerError, noiseStatus, ...
    'VariableNames', {'ComparisonID','FixedNoiseVariance', ...
    'GeometryNoiseVariance','Error_dB','FixedRxPower_dBm', ...
    'GeometryRxPower_dBm','PowerError_dB','Status'});

metricNames = ["BER","BLER","PostEqSINR_dB"];
n = height(source);
comparisonID = repelem(string(source.ComparisonID), 3, 1);
metric = repmat(metricNames(:), n, 1);
fixedValue = reshape([source.FixedBER, source.FixedBLER, ...
    source.FixedPostEqSINR_dB].', [], 1);
geometryValue = reshape([source.GeometryBER, source.GeometryBLER, ...
    source.GeometryPostEqSINR_dB].', [], 1);
difference = abs(fixedValue - geometryValue);
tolerance = zeros(3 * n, 1);
status = repmat("PASS", 3 * n, 1);
status(~isfinite(difference) | difference > tolerance) = "FAIL";
kpi = table(comparisonID, metric, fixedValue, geometryValue, ...
    difference, tolerance, status, ...
    'VariableNames', {'ComparisonID','KPI','FixedValue', ...
    'GeometryValue','Difference','Tolerance','Status'});
if any(waveform.Status ~= "PASS") || ...
        any(receiver.Status ~= "PASS") || ...
        any(noise.Status ~= "PASS") || any(kpi.Status ~= "PASS")
    error("sixgr:integration:CrossModeMismatch", ...
        "Derived cross-mode evidence contains a failed comparison.");
end
end

function root = localRepoRoot()
here = fileparts(mfilename("fullpath"));
root = fileparts(fileparts(here));
end
