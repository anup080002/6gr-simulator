function summary = runTwoModeIntegrationAcceptance(varargin)
%RUNTWOMODEINTEGRATIONACCEPTANCE Fail-closed full actual-run entry point.
%
% This entry point intentionally refuses to substitute focused reduction
% evidence for the 23 mandatory production scenario executions.

p = inputParser;
p.addParameter("RunMatrix","",@(x)ischar(x)||isstring(x));
p.addParameter("OutputDir","",@(x)ischar(x)||isstring(x));
p.addParameter("SeedList",[11 23 47 89 131 197],@isnumeric);
p.addParameter("Strict",true,@(x)islogical(x)&&isscalar(x));
p.addParameter("ActualRunTable",table(),@istable);
p.parse(varargin{:});
opt = p.Results;
if ~opt.Strict
    error("sixgr:integration:StrictRequired", ...
        "Phase-16 acceptance requires Strict=true.");
end
matrix = localRead(string(opt.RunMatrix));
mandatory = matrix(upper(matrix.MustRun)=="YES",:);
actual = opt.ActualRunTable;
requiredColumns = ["CaseID","RunID","Status","OutputPath", ...
    "ResolvedConfigSHA256","ArtifactManifestSHA256"];
complete = istable(actual) && all(ismember(requiredColumns, ...
    string(actual.Properties.VariableNames))) && ...
    height(actual) >= height(mandatory) && ...
    all(ismember(mandatory.CaseID,string(actual.CaseID))) && ...
    all(upper(string(actual.Status))=="COMPLETED");
if ~complete
    summary = struct("Passed",false,"Status","FAIL", ...
        "MandatoryRunsExpected",height(mandatory), ...
        "MandatoryRunsObserved",height(actual), ...
        "AcceptanceRulesEvaluated",0,"CSVArtifactsGenerated",0, ...
        "PNGArtifactsGenerated",0,"OutputDir",string(opt.OutputDir), ...
        "SeedList",double(opt.SeedList(:)).', ...
        "FailureCode","sixgr:integration:MissingActualRunEvidence");
    error("sixgr:integration:MissingActualRunEvidence", ...
        "Full Phase-16 acceptance requires %d completed production run " + ...
        "rows bound to resolved-config and artifact-manifest hashes; got %d.", ...
        height(mandatory),height(actual));
end
error("sixgr:integration:AcceptanceEvaluatorUnavailable", ...
    "Actual runs are present, but the 120-rule evaluator is not yet installed.");
end

function value = localRead(path)
if ~isfile(path)
    error("sixgr:integration:IncompleteConfiguration", ...
        "RunMatrix does not exist: %s.",path);
end
options = detectImportOptions(path,"Delimiter",",","VariableNamingRule","preserve");
options.DataLines = [2 Inf];
options = setvartype(options,options.VariableNames,"string");
value = readtable(path,options);
end
