classdef CommonAirInterfacePipeline
    %COMMONAIRINTERFACEPIPELINE Shared production PHY path for both modes.
    %
    % The environment adapter is the only mode-dependent operation.  The
    % transport-channel coding, NR grid mapping, OFDM waveform and receiver
    % are the production PDSCH/DL-SCH or PUSCH/UL-SCH implementations.

    methods (Static)
        function result = executeReduction(direction, channel, snrDB, seed, mode)
            direction = upper(string(direction));
            channel = upper(string(channel));
            mode = upper(string(mode));
            if ~ismember(direction, ["DL","UL"])
                error("sixgr:integration:RunModeConflict", ...
                    "Direction must be DL or UL.");
            end
            if channel ~= "AWGN" && ~startsWith(channel, "TDL")
                error("sixgr:integration:HiddenNormalization", ...
                    "Reduction channel must be AWGN or a concrete TDL profile.");
            end

            [tx, bits, carrier, physicalChannel, receive] = ...
                localProductionTransmission(direction, channel, seed);
            waveform = complex(double(tx.Waveform));
            [cleanSamples, channelMetadata] = ...
                sixgr.integration.ChannelApplicationContract.apply( ...
                waveform, physicalChannel);
            calibration = ...
                sixgr.phy.waveform.calibrateOFDMNoiseTransform(carrier);
            sampleToGridGain = double( ...
                calibration.SampleToGridNoiseVarianceGain);
            noiseVariance = 10.^(-double(snrDB) / 10) / ...
                sampleToGridGain;
            noiseStream = RandStream("Threefry", ...
                "Seed", double(seed) + 104729);
            noiseUnit = (randn(noiseStream, size(waveform)) + ...
                1j * randn(noiseStream, size(waveform))) / sqrt(2);

            if mode == sixgr.integration.RunMode.FixedSNRSweep
                adapter = sixgr.integration.FixedSNREnvironmentAdapter(seed);
                environment = adapter.apply(cleanSamples, snrDB, ...
                    "NoiseUnitSamples", noiseUnit, ...
                    "NoiseVariance", noiseVariance, ...
                    "SampleToGridNoiseVarianceGain", ...
                    sampleToGridGain);
            elseif mode == "GEOMETRY_NETWORK_NEUTRALIZED" || ...
                    mode == sixgr.integration.RunMode.GeometryNetwork
                adapter = sixgr.integration. ...
                    GeometryNetworkEnvironmentAdapter(seed);
                item = struct("Samples", waveform, ...
                    "Link", physicalChannel);
                environment = adapter.apply({item}, noiseVariance, ...
                    "NoiseUnitSamples", noiseUnit, ...
                    "SampleToGridNoiseVarianceGain", ...
                    sampleToGridGain);
                environment.ConfiguredSNR_dB = NaN;
                environment.AnalyticalInputSNR_dB = double(snrDB);
            else
                error("sixgr:integration:RunModeConflict", ...
                    "Unknown reduction mode.");
            end

            rx = receive(environment.Samples, environment.NoiseVariance);
            decoded = localDecodedBits(rx);
            compared = min(numel(decoded), numel(bits));
            bitErrors = nnz(decoded(1:compared) ~= bits(1:compared)) + ...
                abs(numel(decoded) - numel(bits));
            postSINR = localPostEqualizationSINR(direction, rx);
            crcPass = logical(sixgr.util.structGet(rx, ...
                "TBCRCPass", sixgr.util.structGet(rx, "Ok", false)));
            waveformDigest = sixgr.integration.IntegrationHash.data( ...
                localComplex(waveform));
            receiverPayload = struct( ...
                "Direction", direction, ...
                "DecodedBits", int8(decoded(:)).', ...
                "CRCPass", crcPass, ...
                "BitErrors", double(bitErrors), ...
                "PostEqualizationSINR_dB", double(postSINR), ...
                "ProductionReceiver", localReceiverName(direction));

            result = struct( ...
                "Direction", direction, "Channel", channel, ...
                "Mode", mode, "Seed", double(seed), ...
                "SNR_dB", double(snrDB), ...
                "Bits", int8(bits(:)), "Grid", tx.Grid, ...
                "TxSamples", waveform, ...
                "RxSamples", environment.Samples, ...
                "DecodedBits", int8(decoded(:)), ...
                "BitErrors", double(bitErrors), ...
                "BER", double(bitErrors) / max(numel(bits), 1), ...
                "BLER", double(~crcPass), ...
                "CRCPass", crcPass, ...
                "ConfiguredSNR_dB", environment.ConfiguredSNR_dB, ...
                "AnalyticalInputSNR_dB", ...
                    environment.AnalyticalInputSNR_dB, ...
                "MeasuredInputSNR_dB", environment.MeasuredInputSNR_dB, ...
                "PostEqualizationSINR_dB", double(postSINR), ...
                "WaveformSHA256", waveformDigest, ...
                "ReceivedSHA256", ...
                    sixgr.integration.IntegrationHash.data( ...
                    localComplex(environment.Samples)), ...
                "ReceiverSHA256", ...
                    sixgr.integration.IntegrationHash.data(receiverPayload), ...
                "DecodedBitsSHA256", ...
                    sixgr.integration.IntegrationHash.data( ...
                    int8(decoded(:)).'), ...
                "WaveformImplementationSHA256", ...
                    sixgr.integration.IntegrationHash.file( ...
                    localWaveformImplementation(direction)), ...
                "ReceiverImplementationSHA256", ...
                    sixgr.integration.IntegrationHash.file( ...
                    localReceiverImplementation(direction)), ...
                "ProductionBackend", ...
                    "production_" + lower(direction) + ...
                    "_sch_nr_waveform_chain", ...
                "ApproximationMode", "none", ...
                "Carrier", carrier, ...
                "ChannelMetadata", channelMetadata, ...
                "Environment", environment, ...
                "Receiver", rx);
        end
    end
end

function [tx, bits, carrier, link, receive] = ...
        localProductionTransmission(direction, channel, seed)
targetCodeRate = 0.30;
cfg = sixgr.config.defaultConfig();
cfg.run.strictMode = false;
cfg.run.noiseOperatingMode = "standalone_awgn_snr_argument";
cfg.channel.model = char(channel);
cfg.channel.nTxAnt = 1;
cfg.channel.nRxAnt = 1;
cfg.phy.nTxAnt = 1;
cfg.phy.nRxAnt = 1;
cfg.phy.carrier.NSizeGrid = 12;
cfg.phy.carrier.SubcarrierSpacing = 30;
cfg.phy.carrier.NCellID = 42;
cfg.run.pdschExecutionProfile = "phy_calibration";
cfg.phy.pdsch.executionProfile = "phy_calibration";
cfg.phy.pdsch.modulation = "QPSK";
cfg.phy.pdsch.codeRate = targetCodeRate;
cfg.phy.pdsch.prbSet = 0:5;
cfg.phy.pdsch.symbolAllocation = [0 10];
cfg.phy.pdsch.mappingType = "A";
cfg.phy.pdsch.nLayers = 1;
cfg.phy.pdsch.numLayers = 1;
cfg.phy.pdsch.numPorts = 1;
cfg.phy.pdsch.nPorts = 1;
cfg.phy.pdsch.dmrs.nPorts = 1;
cfg.phy.pdsch.enablePTRS = false;
cfg.phy.pdsch.mcsTable = "calibration_explicit";
cfg.phy.pdsch.mcsIndex = 0;
cfg.phy.pdsch.mcsContext = struct( ...
    "UECapability1024QAM", false, ...
    "RRCEnabled1024QAM", false, ...
    "DCIEnabled1024QAM", false, ...
    "DeploymentAllows1024QAM", false, ...
    "FrequencyRangeAllows1024QAM", false, ...
    "BandAllows1024QAM", false, ...
    "FrequencyRange", "FR1", ...
    "OperatingBand", "n78", ...
    "DeploymentClass", "controlled_test");
cfg.phy.csirs.enabled = false;
cfg.phy.csirs.nPorts = 1;
cfg.phy.pusch.modulation = "QPSK";
cfg.phy.pusch.codeRate = targetCodeRate;
cfg.phy.pusch.prbSet = 0:5;
cfg.phy.pusch.symbolAllocation = [0 10];
cfg.phy.pusch.mappingType = "A";
cfg.phy.pusch.nLayers = 1;
cfg.phy.pusch.numLayers = 1;
cfg.phy.pusch.numPorts = 1;
cfg.phy.pusch.nPorts = 1;
cfg.phy.pusch.dmrs.nPorts = 1;
cfg.phy.pusch.transformPrecoding = false;
cfg.phy.pusch.mcsTable = "calibration_explicit";
cfg.phy.pusch.mcsIndex = 0;
previousRng = rng;
restoreRng = onCleanup(@() rng(previousRng));
rng(mod(double(seed), 2^32), "twister");

if direction == "DL"
    [tx, ~] = sixgr.phy.dl.PDSCH_Tx(cfg, ...
        "TargetCodeRate", targetCodeRate, "RV", 0, ...
        "NumTxAnt", 1, "ExecutionProfile", "phy_calibration", ...
        "CompactOutput", false);
    bits = int8(tx.TransportBlock(:));
    carrier = tx.Carrier;
    pdsch = tx.PDSCH;
    receive = @(waveform, noiseVariance) ...
        sixgr.phy.dl.PDSCH_Rx(waveform, cfg, ...
        "Carrier", carrier, "PDSCH", pdsch, ...
        "PDSCHIndices", tx.PDSCHIndices, ...
        "TransportBlockSize", tx.TransportBlockSize, ...
        "TargetCodeRate", targetCodeRate, "RV", 0, ...
        "NoiseVar", noiseVariance, "NoiseVarDomain", "time", ...
        "CodingLayout", tx.CodingLayouts, ...
        "CodingPlan", tx.CodingPlans, ...
        "FastAWGNPath", false, "SkipTimingEstimate", true, ...
        "ExecutionProfile", "phy_calibration", ...
        "CompactOutput", false);
else
    [tx, ~] = sixgr.phy.ul.PUSCH_Tx(cfg, ...
        "TargetCodeRate", targetCodeRate, "RV", 0, ...
        "NumTxAnt", 1, "CompactOutput", false);
    bits = int8(tx.TransportBlock(:));
    carrier = tx.Carrier;
    pusch = tx.PUSCH;
    receive = @(waveform, noiseVariance) ...
        sixgr.phy.ul.PUSCH_Rx(waveform, cfg, ...
        "Carrier", carrier, "PUSCH", pusch, ...
        "PUSCHIndices", tx.PUSCHIndices, ...
        "TransportBlockSize", tx.TransportBlockSize, ...
        "TargetCodeRate", targetCodeRate, "RV", 0, ...
        "CodingLayout", tx.CodingLayouts, ...
        "NoiseVar", noiseVariance, "NoiseVarDomain", "time", ...
        "ConfiguredNoiseVariance", noiseVariance, ...
        "FastAWGNPath", false, "SkipTimingEstimate", true, ...
        "CompactOutput", false);
end

if channel == "AWGN"
    impulse = 1;
else
    impulse = [0.92; 0.24 * exp(1j * 0.37); ...
        0.11 * exp(-1j * 0.51)];
end
link = struct( ...
    "LinkID", "DESIRED-1", ...
    "GainLinear", 1, ...
    "ImpulseResponse", impulse, ...
    "DelaySamples", 0, ...
    "FrequencyOffsetHz", 0, ...
    "SampleRateHz", carrier.SubcarrierSpacing * 1e3 * ...
        double(tx.OFDM.Nfft), ...
    "Normalize", false);
end

function decoded = localDecodedBits(rx)
if isfield(rx, "TransportBlocks") && iscell(rx.TransportBlocks)
    decoded = vertcat(rx.TransportBlocks{:});
elseif isfield(rx, "TransportBlock")
    decoded = rx.TransportBlock;
else
    error("sixgr:integration:ReceiverOracleInput", ...
        "Production receiver did not emit decoded transport-block bits.");
end
decoded = int8(decoded(:));
end

function value = localPostEqualizationSINR(direction, rx)
if direction == "DL"
    value = mean(double(sixgr.util.structGet(rx, ...
        "Metrics.MeasuredPostEqualizationSINRdBPerLayer", NaN)), ...
        "omitnan");
else
    value = mean(double(sixgr.util.structGet(rx, ...
        "PostEqSINRPerLayer_dB", ...
        sixgr.util.structGet(rx, "PostEqSINR_dB", NaN))), ...
        "omitnan");
end
if ~isfinite(value)
    error("sixgr:integration:MissingActualRunEvidence", ...
        "Production receiver did not emit finite post-equalization SINR.");
end
end

function output = localWaveformImplementation(direction)
if direction == "DL"
    output = which("sixgr.phy.dl.PDSCH_Tx");
else
    output = which("sixgr.phy.ul.PUSCH_Tx");
end
end

function output = localReceiverImplementation(direction)
if direction == "DL"
    output = which("sixgr.phy.dl.PDSCH_Rx");
else
    output = which("sixgr.phy.ul.PUSCH_Rx");
end
end

function output = localReceiverName(direction)
if direction == "DL"
    output = "sixgr.phy.dl.PDSCH_Rx";
else
    output = "sixgr.phy.ul.PUSCH_Rx";
end
end

function value = localComplex(input)
value = struct("Real", real(double(input(:))).', ...
    "Imag", imag(double(input(:))).', "Size", size(input));
end
