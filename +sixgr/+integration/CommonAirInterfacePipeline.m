classdef CommonAirInterfacePipeline
    %COMMONAIRINTERFACEPIPELINE One sample/grid/receiver path for both modes.
    methods (Static)
        function result = executeReduction(direction,channel,snrDB,seed,mode)
            direction = upper(string(direction));
            channel = upper(string(channel));
            mode = upper(string(mode));
            if ~ismember(direction,["DL","UL"])
                error("sixgr:integration:RunModeConflict","Direction must be DL or UL.");
            end
            stream = RandStream("Threefry","Seed",double(seed));
            nOccupied = 24; nfft = 64; cp = repmat(8,1,4);
            bitCount = 2*nOccupied*numel(cp);
            bits = randi(stream,[0 1],bitCount,1);
            symbols = ((1-2*bits(1:2:end)) + ...
                1j*(1-2*bits(2:2:end)))/sqrt(2);
            grid = reshape(symbols,nOccupied,numel(cp));
            [tx,ofdmInfo] = sixgr.phy.waveform.CanonicalOFDMModulator.math( ...
                grid,nfft,cp);
            if channel == "AWGN"
                impulse = 1;
            elseif startsWith(channel,"TDL")
                impulse = [0.92;0.24*exp(1j*.37);0.11*exp(-1j*.51)];
            else
                error("sixgr:integration:HiddenNormalization", ...
                    "Reduction channel must be AWGN or a concrete TDL profile.");
            end
            link = struct("LinkID","DESIRED-1","GainLinear",1, ...
                "ImpulseResponse",impulse,"DelaySamples",0, ...
                "FrequencyOffsetHz",0,"SampleRateHz",1.92e6, ...
                "Normalize",false);
            [channelOutput,channelMetadata] = ...
                sixgr.integration.ChannelApplicationContract.apply(tx,link);
            noiseStream = RandStream("Threefry","Seed",double(seed)+104729);
            noiseUnit = (randn(noiseStream,size(tx)) + ...
                1j*randn(noiseStream,size(tx)))/sqrt(2);
            signalPower = mean(abs(channelOutput(:)).^2);
            noiseVariance = signalPower/10^(double(snrDB)/10);
            if mode == sixgr.integration.RunMode.FixedSNRSweep
                adapter = sixgr.integration.FixedSNREnvironmentAdapter(seed);
                environment = adapter.apply(channelOutput,snrDB, ...
                    "NoiseUnitSamples",noiseUnit);
            elseif mode == "GEOMETRY_NETWORK_NEUTRALIZED" || ...
                    mode == sixgr.integration.RunMode.GeometryNetwork
                adapter = sixgr.integration.GeometryNetworkEnvironmentAdapter(seed);
                item = struct("Samples",tx,"Link",link);
                environment = adapter.apply({item},noiseVariance, ...
                    "NoiseUnitSamples",noiseUnit);
                environment.ConfiguredSNR_dB = NaN;
                environment.AnalyticalInputSNR_dB = double(snrDB);
            else
                error("sixgr:integration:RunModeConflict","Unknown reduction mode.");
            end
            receiver = sixgr.integration.CommonReceiverPipeline.recover( ...
                environment.Samples,environment.CleanSamples, ...
                environment.NoiseSamples,nfft,cp,nOccupied,bits);
            waveformDigest = sixgr.integration.IntegrationHash.data( ...
                localComplex(tx));
            result = struct("Direction",direction,"Channel",channel, ...
                "Mode",mode,"Seed",double(seed),"SNR_dB",double(snrDB), ...
                "Bits",bits,"Grid",grid,"TxSamples",tx, ...
                "RxSamples",environment.Samples, ...
                "DecodedBits",receiver.DecodedBits, ...
                "BitErrors",receiver.BitErrors,"BER",receiver.BER, ...
                "ConfiguredSNR_dB",environment.ConfiguredSNR_dB, ...
                "AnalyticalInputSNR_dB",environment.AnalyticalInputSNR_dB, ...
                "MeasuredInputSNR_dB",environment.MeasuredInputSNR_dB, ...
                "PostEqualizationSINR_dB", ...
                receiver.PostEqualizationSINR_dB, ...
                "WaveformSHA256",waveformDigest, ...
                "ReceivedSHA256",sixgr.integration.IntegrationHash.data( ...
                localComplex(environment.Samples)), ...
                "ReceiverSHA256",receiver.ReceiverResultSHA256, ...
                "DecodedBitsSHA256",sixgr.integration.IntegrationHash.data( ...
                receiver.DecodedBits.'), ...
                "WaveformImplementationSHA256", ...
                sixgr.integration.IntegrationHash.file(which( ...
                "sixgr.phy.waveform.CanonicalOFDMModulator")), ...
                "ReceiverImplementationSHA256", ...
                receiver.ImplementationSHA256, ...
                "OFDMInfo",ofdmInfo,"ChannelMetadata",channelMetadata, ...
                "Environment",environment);
        end
    end
end

function value = localComplex(input)
value = struct("Real",real(double(input(:))).', ...
    "Imag",imag(double(input(:))).',"Size",size(input));
end
