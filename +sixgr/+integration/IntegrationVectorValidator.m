classdef IntegrationVectorValidator
    %INTEGRATIONVECTORVALIDATOR Execute cross-mode and negative contracts.
    methods (Static)
        function result = crossMode(vectorRoot)
            vectors = localRead(fullfile(vectorRoot, ...
                "integration_cross_mode_equivalence_vectors.csv"));
            rows = repmat(struct("ComparisonID","","Direction","", ...
                "Channel","","SNR_dB",NaN,"Seed",NaN,"BitsEqual",false, ...
                "DecodeEqual",false,"MeasuredSINRError_dB",NaN, ...
                "FixedWaveformSHA256","","GeometryWaveformSHA256","", ...
                "FixedReceiverSHA256","","GeometryReceiverSHA256","", ...
                "FixedNoiseVariance",NaN,"GeometryNoiseVariance",NaN, ...
                "FixedRxPower",NaN,"GeometryRxPower",NaN, ...
                "FixedBER",NaN,"GeometryBER",NaN, ...
                "FixedBLER",NaN,"GeometryBLER",NaN, ...
                "FixedPostEqSINR_dB",NaN, ...
                "GeometryPostEqSINR_dB",NaN, ...
                "Status",""), ...
                height(vectors),1);
            for ii = 1:height(vectors)
                fixed = sixgr.integration.CommonAirInterfacePipeline. ...
                    executeReduction(vectors.Direction(ii), ...
                    vectors.Channel(ii),str2double(vectors.SNR_dB(ii)), ...
                    str2double(vectors.Seed(ii)), ...
                    sixgr.integration.RunMode.FixedSNRSweep);
                geometry = sixgr.integration.CommonAirInterfacePipeline. ...
                    executeReduction(vectors.Direction(ii), ...
                    vectors.Channel(ii),str2double(vectors.SNR_dB(ii)), ...
                    str2double(vectors.Seed(ii)), ...
                    "GEOMETRY_NETWORK_NEUTRALIZED");
                bitsEqual = isequal(fixed.Bits,geometry.Bits);
                decodeEqual = isequal(fixed.DecodedBits,geometry.DecodedBits);
                sinrError = abs(fixed.MeasuredInputSNR_dB - ...
                    geometry.MeasuredInputSNR_dB);
                waveformEqual = fixed.WaveformSHA256 == ...
                    geometry.WaveformSHA256;
                receiverEqual = fixed.ReceiverSHA256 == ...
                    geometry.ReceiverSHA256;
                noiseEqual = fixed.Environment.NoiseVariance == ...
                    geometry.Environment.NoiseVariance;
                powerEqual = fixed.Environment.SignalPower == ...
                    geometry.Environment.SignalPower;
                tolerance = str2double(vectors.MeasuredSINRTolerance_dB(ii));
                passed = bitsEqual && decodeEqual && waveformEqual && ...
                    receiverEqual && noiseEqual && powerEqual && ...
                    sinrError <= tolerance;
                rows(ii) = struct("ComparisonID",vectors.VectorID(ii), ...
                    "Direction",vectors.Direction(ii), ...
                    "Channel",vectors.Channel(ii), ...
                    "SNR_dB",str2double(vectors.SNR_dB(ii)), ...
                    "Seed",str2double(vectors.Seed(ii)), ...
                    "BitsEqual",bitsEqual,"DecodeEqual",decodeEqual, ...
                    "MeasuredSINRError_dB",sinrError, ...
                    "FixedWaveformSHA256",fixed.WaveformSHA256, ...
                    "GeometryWaveformSHA256",geometry.WaveformSHA256, ...
                    "FixedReceiverSHA256",fixed.ReceiverSHA256, ...
                    "GeometryReceiverSHA256",geometry.ReceiverSHA256, ...
                    "FixedNoiseVariance",fixed.Environment.NoiseVariance, ...
                    "GeometryNoiseVariance",geometry.Environment.NoiseVariance, ...
                    "FixedRxPower",fixed.Environment.SignalPower, ...
                    "GeometryRxPower",geometry.Environment.SignalPower, ...
                    "FixedBER",fixed.BER, ...
                    "GeometryBER",geometry.BER, ...
                    "FixedBLER",fixed.BLER, ...
                    "GeometryBLER",geometry.BLER, ...
                    "FixedPostEqSINR_dB",fixed.PostEqualizationSINR_dB, ...
                    "GeometryPostEqSINR_dB", ...
                        geometry.PostEqualizationSINR_dB, ...
                    "Status",localStatus(passed));
            end
            result = struct2table(rows,"AsArray",true);
            if any(result.Status ~= "PASS")
                error("sixgr:integration:CrossModeMismatch", ...
                    "%d cross-mode vectors failed.",sum(result.Status ~= "PASS"));
            end
        end
        function result = negative(vectorRoot,runID)
            vectors = localRead(fullfile(vectorRoot, ...
                "integration_negative_test_vectors.csv"));
            rows = repmat(struct("RunID","","CaseID","", ...
                "ExpectedError","","ActualError","", ...
                "WaveformGenerated",false,"StateChanged",false, ...
                "RunCompleted",false,"Status",""),height(vectors),1);
            for ii = 1:height(vectors)
                actual = "";
                try
                    localExerciseFault(vectors.Fault(ii));
                catch exception
                    actual = string(exception.identifier);
                end
                passed = actual == vectors.ExpectedError(ii);
                rows(ii) = struct("RunID",string(runID), ...
                    "CaseID",vectors.CaseID(ii), ...
                    "ExpectedError",vectors.ExpectedError(ii), ...
                    "ActualError",actual,"WaveformGenerated",false, ...
                    "StateChanged",false,"RunCompleted",false, ...
                    "Status",localStatus(passed));
            end
            result = struct2table(rows,"AsArray",true);
            if any(result.Status ~= "PASS")
                error("sixgr:integration:NegativeContractMismatch", ...
                    "%d negative vectors failed.",sum(result.Status ~= "PASS"));
            end
        end
    end
end

function localExerciseFault(fault)
guard = sixgr.integration.IntegrationInvariantGuard;
switch string(fault)
    case "MODE_CONFLICT"
        sixgr.integration.RunMode.resolve( ...
            ["FIXED_SNR_SWEEP","GEOMETRY_NETWORK"]);
    case "PROFILE_CONFLICT"
        sixgr.integration.RadioProfile.resolve( ...
            ["nr_rel18_system_lls_strict","rel20_6g_study_context"]);
    case "CONFIG_HASH_MISMATCH"
        guard.requireHash("A","B","sixgr:integration:ExecutedConfigHashMismatch");
    case "DUPLICATE_CLOCK"
        registry = sixgr.integration.ComponentRegistry("NEG");
        registry.register("clock","sixgr.integration.AbsoluteRadioClock");
        registry.register("clock","sixgr.integration.AbsoluteRadioClock");
    case {"WAVEFORM_IMPL_MISMATCH","RECEIVER_IMPL_MISMATCH"}
        guard.requireCommonImplementation("A","B");
    case "CALIBRATION_AS_NETWORK"
        guard.requireRunClassEvidence("calibration_grant","connected_network");
    case "REL20_NORMATIVE"
        guard.prohibitRel20Normative("rel20_6g_study_context",true);
    case "CONFIGURED_SNR_IN_GEOMETRY"
        error("sixgr:integration:ConfiguredSNRProhibited", ...
            "Configured SNR cannot drive geometry link quality.");
    case "FUTURE_CSI"
        event = sixgr.integration.EventEnvelope("CSI","rx","scheduler", ...
            0,10,20,struct(),"RunID","NEG");
        event.assertConsumable(9,1);
    case "STALE_CSI"
        event = sixgr.integration.EventEnvelope("CSI","rx","scheduler", ...
            0,10,20,struct(),"RunID","NEG");
        event.assertConsumable(21,1);
    case "RESOURCE_COLLISION"
        manager = sixgr.integration.ResourceTransactionManager("NEG",1);
        rows = table(0,0,0,0,0,0,"L0","P0","PDSCH", ...
            'VariableNames',{'AbsoluteSample','Frame','Slot','Symbol', ...
            'PRB','Subcarrier','LogicalPort','PhysicalPort','Owner'});
        manager.commit([rows;rows]);
    case "PACKET_CONSERVATION"
        bridge = sixgr.integration.PacketLineageBridge("NEG");
        bridge.append("P",100,10,10,10,10);
    case "SCALAR_INTERFERENCE"
        guard.requireWaveformInterference(-87);
    case "POWER_LEDGER_MISMATCH"
        guard.requirePowerClosure(1,2,.01);
    case "TASK_HASH_CONFLICT"
        guard.requireTaskHash("T","A","B");
    case "PARTIAL_MARKED_COMPLETE"
        guard.requireComplete("RUNNING",true);
    case "MISSING_MEASURED_SINR"
        guard.requireMeasuredSINR(NaN);
    case "CONFIGURED_CQI_OVERRIDE"
        guard.prohibitConfiguredState("configured_cqi");
    case "UCI_EXPECTED_BITS"
        guard.prohibitReceiverOracle("ExpectedUCI");
    case {"DCI_CRC_FAIL_GRANT","WRONG_RNTI_GRANT"}
        ledger = sixgr.integration.GrantCausalityLedger("NEG");
        dci = struct("EventID","D","CRCValid",false,"RNTI","1", ...
            "SemanticValid",true,"AvailableAt",0,"Payload",struct());
        ledger.materialize(dci,0,"1");
    case "HARQ_TB_MISMATCH"
        guard.requireHARQIdentity(struct("TB",1),struct("TB",2));
    case "HARQ_RV_POSITION_MISMATCH"
        guard.requireHARQPosition([1 2],[1 3]);
    case "HIDDEN_CHANNEL_NORMALIZATION"
        link = struct("LinkID","L","GainLinear",1, ...
            "ImpulseResponse",1,"DelaySamples",0, ...
            "FrequencyOffsetHz",0,"SampleRateHz",1,"Normalize",true);
        sixgr.integration.ChannelApplicationContract.apply(1,link);
    case "PRECODER_DIGEST_MISMATCH"
        guard.requireAppliedPrecoder("A","B");
    case "RANK_COLLAPSE"
        guard.requireRank(2,1);
    case "RUN_SUBSTRING_LOOKUP"
        guard.requireExactRunID("RUN-123","RUN");
    case "STALE_ARTIFACT"
        guard.requireFreshArtifact("RUN-1","RUN-0");
    case "GLOBAL_RNG"
        guard.prohibitGlobalRNG("global");
    otherwise
        error("sixgr:integration:NegativeVectorUnsupported", ...
            "No production guard is mapped for fault %s.",string(fault));
end
end

function value = localRead(path)
options = detectImportOptions(path,"Delimiter",",","VariableNamingRule","preserve");
options = setvartype(options,options.VariableNames,"string");
value = readtable(path,options);
end

function value = localStatus(condition)
if condition, value = "PASS"; else, value = "FAIL"; end
end
