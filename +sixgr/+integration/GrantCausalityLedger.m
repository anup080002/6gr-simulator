classdef GrantCausalityLedger < handle
    %GRANTCAUSALITYLEDGER Bind materialized grants to decoded control.
    properties (SetAccess=immutable)
        RunID (1,1) string
    end
    properties (Access=private)
        Rows
    end
    methods
        function obj = GrantCausalityLedger(runID)
            obj.RunID = string(runID);
            variableTypes = ["string","string","string","string", ...
                "double","double","string","string","string"];
            variableNames = ["RunID","GrantID","SourceEventID","RNTI", ...
                "ProducedAt","ConsumedAt","CRCStatus","SemanticStatus","Status"];
            obj.Rows = table('Size',[0 9], ...
                'VariableTypes',cellstr(variableTypes), ...
                'VariableNames',cellstr(variableNames));
        end
        function grantID = materialize(obj,decodedDCI,now,expectedRNTI)
            required = ["EventID","CRCValid","RNTI","SemanticValid", ...
                "AvailableAt","Payload"];
            if ~isstruct(decodedDCI) || ...
                    ~all(isfield(decodedDCI,cellstr(required))) || ...
                    ~logical(decodedDCI.CRCValid) || ...
                    ~logical(decodedDCI.SemanticValid) || ...
                    string(decodedDCI.RNTI) ~= string(expectedRNTI) || ...
                    double(now) < double(decodedDCI.AvailableAt)
                error("sixgr:integration:InvalidGrantCausality", ...
                    "A dynamic grant requires available CRC/RNTI/semantic-valid decoded DCI.");
            end
            grantID = "GRANT-" + extractBefore( ...
                sixgr.integration.IntegrationHash.data(struct( ...
                "Source",decodedDCI.EventID,"Payload",decodedDCI.Payload)),13);
            obj.Rows(end+1,:) = {obj.RunID,grantID,string(decodedDCI.EventID), ...
                string(decodedDCI.RNTI),double(decodedDCI.AvailableAt), ...
                double(now),"PASS","PASS","PASS"};
        end
        function value = table(obj)
            value = obj.Rows;
        end
    end
end
