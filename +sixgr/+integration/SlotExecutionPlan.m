classdef SlotExecutionPlan
    %SLOTEXECUTIONPLAN Immutable event-stage ordering for one absolute slot.
    properties (SetAccess=immutable)
        AbsoluteSlot (1,1) double
        Stages (:,1) string
        PlanSHA256 (1,1) string
    end
    methods
        function obj = SlotExecutionPlan(absoluteSlot)
            obj.AbsoluteSlot = double(absoluteSlot);
            obj.Stages = ["advance_clock";"apply_environment_events"; ...
                "generate_traffic";"release_measurements";"project_state"; ...
                "scheduler_snapshot";"candidate_grants"; ...
                "validate_transactions";"commit_transactions"; ...
                "build_resource_grids";"generate_waveforms"; ...
                "apply_channel_rf_interference";"receive_decode"; ...
                "emit_decoded_events";"update_protocol_state"; ...
                "export_incremental_evidence"];
            obj.PlanSHA256 = sixgr.integration.IntegrationHash.data( ...
                struct("AbsoluteSlot",obj.AbsoluteSlot,"Stages",obj.Stages));
        end
    end
end
