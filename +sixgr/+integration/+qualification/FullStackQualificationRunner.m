classdef FullStackQualificationRunner
    %FULLSTACKQUALIFICATIONRUNNER Orchestrate one immutable Phase-18 suite.
    %
    % Scientific work is delegated to the canonical domain runners. This
    % class owns execution order, immutable binding, evidence aggregation,
    % artifact verification, publication and the final fail-closed verdict.

    methods (Static)
        function result = run(cfg, scfg, runFolder)
            arguments
                cfg (1,1) struct
                scfg (1,1) sixgr.lls6g.config.ScenarioConfig
                runFolder (1,1) string
            end

            profile = sixgr.integration.qualification. ...
                FullStackQualificationProfile.load(scfg);
            ctx = sixgr.integration.qualification. ...
                FullStackRunContext.create(cfg, scfg, runFolder, profile);
            registry = sixgr.integration.qualification. ...
                FullStackSubcaseRegistry.load(profile);
            [implementation, implementationHash] = ...
                sixgr.integration.qualification. ...
                CanonicalComponentRegistry.build(profile);
            implementation.RunID = repmat(ctx.RunID, height(implementation), 1);
            implementation = movevars(implementation, "RunID", "Before", 1);
            sixgr.util.csvWriteTable(fullfile(ctx.CSVDir, ...
                "full_stack_canonical_implementation_registry.csv"), ...
                implementation);

            outcomes = localExecuteGroups(ctx, registry);
            subcases = localBuildSubcaseStatus(ctx, registry, outcomes, ...
                implementationHash, struct());
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeSubcases(ctx, subcases);

            negatives = sixgr.integration.qualification. ...
                FullStackNegativeFaultExecutor.execute(ctx);
            causality = sixgr.integration.qualification. ...
                CrossDomainCausalityLedger.build(ctx);
            values = sixgr.integration.qualification. ...
                ValueCorrectnessEngine.evaluate(ctx);
            components = sixgr.integration.qualification. ...
                ComponentEvidenceLedger.evaluate(ctx, subcases, values, ...
                implementation);

            % These preliminary files make every integration artifact
            % structurally available before the recursive selected-preset
            % audit. They are real fail-closed evaluations, not placeholders.
            webgui = sixgr.integration.qualification. ...
                WebGUIPublicationLedger.build(ctx);
            regression = sixgr.integration.qualification. ...
                FullStackRegressionRunner.pending(ctx);
            preliminaryAcceptance = sixgr.integration.qualification. ...
                FullStackAcceptanceEvaluator.evaluate(ctx, subcases, ...
                components, values, negatives); %#ok<NASGU>
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeRunManifest(ctx, "FAIL", 2);
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeFailureRegistry(ctx, subcases, components, values, ...
                negatives, preliminaryAcceptance, regression);
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeFigures(ctx);

            artifactAudit = sixgr.integration.qualification. ...
                ArtifactCompletenessEngine.run(ctx);
            regression = sixgr.integration.qualification. ...
                FullStackRegressionRunner.run(ctx);
            % Publication is evaluated again after integration artifacts and
            % regression evidence exist. The preliminary ledger is
            % deliberately fail-closed and cannot be the final WebGUI gate.
            webgui = sixgr.integration.qualification. ...
                WebGUIPublicationLedger.build(ctx);
            special = struct( ...
                "NegativePassed", localRequiredPass(negatives), ...
                "ArtifactPassed", logical(artifactAudit.Passed), ...
                "WebGUIPassed", localRequiredPass(webgui), ...
                "RegressionPassed", localRegressionPass(regression));
            subcases = localBuildSubcaseStatus(ctx, registry, outcomes, ...
                implementationHash, special);
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeSubcases(ctx, subcases);
            components = sixgr.integration.qualification. ...
                ComponentEvidenceLedger.evaluate(ctx, subcases, values, ...
                implementation);

            preAcceptancePass = localRequiredPass(subcases) && ...
                localRequiredPass(components) && ...
                localRequiredPass(values) && ...
                localRequiredPass(negatives) && ...
                logical(artifactAudit.Passed) && ...
                localRequiredPass(webgui) && ...
                localRegressionPass(regression) && ...
                ctx.ResolvedYAMLSHA256 == ctx.ExecutedYAMLSHA256 && ...
                all(string(implementation.Status) == "PASS") && ...
                localCausalityPass(causality);
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeRunManifest(ctx, localStatus(preAcceptancePass), ...
                localExitCode(preAcceptancePass));
            acceptance = sixgr.integration.qualification. ...
                FullStackAcceptanceEvaluator.evaluate(ctx, subcases, ...
                components, values, negatives);
            finalPass = preAcceptancePass && localRequiredPass(acceptance);
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeRunManifest(ctx, localStatus(finalPass), ...
                localExitCode(finalPass));
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeFailureRegistry(ctx, subcases, components, values, ...
                negatives, acceptance, regression);
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeFigures(ctx);

            % Final bytes are rescanned after acceptance/failure/figure
            % updates, so hashes and semantic checks describe the delivered
            % output rather than an earlier intermediate state.
            webgui = sixgr.integration.qualification. ...
                WebGUIPublicationLedger.build(ctx);
            artifactAudit = sixgr.integration.qualification. ...
                ArtifactCompletenessEngine.run(ctx);
            special.ArtifactPassed = logical(artifactAudit.Passed);
            special.WebGUIPassed = localRequiredPass(webgui);
            subcases = localBuildSubcaseStatus(ctx, registry, outcomes, ...
                implementationHash, special);
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeSubcases(ctx, subcases);
            components = sixgr.integration.qualification. ...
                ComponentEvidenceLedger.evaluate(ctx, subcases, values, ...
                implementation);
            preAcceptancePass = localRequiredPass(subcases) && ...
                localRequiredPass(components) && ...
                localRequiredPass(values) && ...
                localRequiredPass(negatives) && ...
                logical(artifactAudit.Passed) && ...
                localRequiredPass(webgui) && ...
                localRegressionPass(regression) && ...
                ctx.ResolvedYAMLSHA256 == ctx.ExecutedYAMLSHA256 && ...
                all(string(implementation.Status) == "PASS") && ...
                localCausalityPass(causality);
            sixgr.integration.qualification.FullStackArtifactExporter. ...
                writeRunManifest(ctx, localStatus(preAcceptancePass), ...
                localExitCode(preAcceptancePass));
            acceptance = sixgr.integration.qualification. ...
                FullStackAcceptanceEvaluator.evaluate(ctx, subcases, ...
                components, values, negatives);
            finalPass = preAcceptancePass && localRequiredPass(acceptance);
            manifest = sixgr.integration.qualification. ...
                FullStackArtifactExporter.writeRunManifest(ctx, ...
                localStatus(finalPass), localExitCode(finalPass));
            failures = sixgr.integration.qualification. ...
                FullStackArtifactExporter.writeFailureRegistry(ctx, ...
                subcases, components, values, negatives, acceptance, ...
                regression);
            imageAudit = sixgr.integration.qualification. ...
                FullStackArtifactExporter.writeFigures(ctx);
            sixgr.integration.qualification. ...
                ArtifactCompletenessEngine.finalizeManifest(ctx);

            result = struct();
            result.Ok = logical(finalPass);
            result.Profile = profile.Preset;
            result.RunID = ctx.RunID;
            result.RunFolder = ctx.RunFolder;
            result.ConfigurationRevisionID = ctx.ConfigurationRevisionID;
            result.ResolvedYAMLSHA256 = ctx.ResolvedYAMLSHA256;
            result.ExecutedYAMLSHA256 = ctx.ExecutedYAMLSHA256;
            result.ImplementationRegistrySHA256 = implementationHash;
            result.SubcaseStatus = subcases;
            result.ComponentCoverage = components;
            result.ValueCorrectness = values;
            result.NegativeResults = negatives;
            result.CrossDomainCausality = causality;
            result.WebGUIPublication = webgui;
            result.AcceptanceResults = acceptance;
            result.RegressionSummary = regression;
            result.ArtifactAudit = artifactAudit;
            result.ImageSemanticAudit = imageAudit;
            result.FailureRegistry = failures;
            result.RunManifest = manifest;
            result.RequiredArtifactCount = profile.ExpectedArtifactCount;
            result.FinalStatus = localStatus(finalPass);
        end
    end
end

function outcomes = localExecuteGroups(ctx, registry)
groups = strings(0,1);
for index = 1:numel(registry)
    group = sixgr.integration.qualification. ...
        ComponentExecutionAdapter.groupFor(registry(index).SubcaseID);
    if ~ismember(group, ["ORCHESTRATOR","REGRESSION"]) && ...
            ~ismember(group, groups)
        groups(end+1,1) = group; %#ok<AGROW>
    end
end
outcomes = repmat(struct("Group","","Executed",false,"Passed",false, ...
    "FailureCode","","Details","","OutputDir","","DurationSeconds",NaN, ...
    "Summary",struct()), numel(groups), 1);
for index = 1:numel(groups)
    outcomes(index) = sixgr.integration.qualification. ...
        ComponentExecutionAdapter.execute(groups(index), ctx);
end
end

function T = localBuildSubcaseStatus(ctx, registry, outcomes, ...
        implementationHash, special)
n = numel(registry);
rows = repmat(localSubcaseRow(), n, 1);
seedText = strjoin(string(sixgr.util.structGet( ...
    ctx.Profile.PresetConfiguration, "fixed_snr_seeds", [])), "|");
artifactIndex = sixgr.integration.qualification. ...
    RunArtifactIndex.build(ctx.RunFolder);
for index = 1:n
    item = registry(index);
    group = sixgr.integration.qualification. ...
        ComponentExecutionAdapter.groupFor(item.SubcaseID);
    started = ctx.StartUTC;
    completed = localUTC();
    executed = false;
    passed = false;
    failureCode = "";
    details = "";
    if group == "ORCHESTRATOR"
        executed = isfield(special, "ArtifactPassed");
        if item.SubcaseID == "SC-28"
            passed = localSpecial(special, "ArtifactPassed");
            failureCode = localFailure(passed, ...
                "FULLSTACK:ArtifactAuditFailed");
            details = "Selected-preset recursive artifact audit.";
        else
            passed = localSpecial(special, "WebGUIPassed");
            failureCode = localFailure(passed, ...
                "FULLSTACK:WebGUIPublicationFailed");
            details = "Canonical WebGUI publication ledger.";
        end
    elseif group == "REGRESSION"
        executed = isfield(special, "RegressionPassed");
        passed = localSpecial(special, "RegressionPassed");
        failureCode = localFailure(passed, ...
            "FULLSTACK:RegressionFailed");
        details = "Ten mandatory regression suites.";
    elseif group == "NEGATIVE"
        mask = string({outcomes.Group}) == group;
        executed = any(mask & [outcomes.Executed]);
        passed = executed && localSpecial(special, "NegativePassed");
        failureCode = localFailure(passed, ...
            "FULLSTACK:NegativeMatrixFailed");
        details = "All mandatory fault injections reject without mutation.";
    else
        mask = string({outcomes.Group}) == group;
        if any(mask)
            outcome = outcomes(find(mask,1));
            executed = logical(outcome.Executed);
            passed = logical(outcome.Passed);
            failureCode = string(outcome.FailureCode);
            details = string(outcome.Details);
            started = localUTCOffset(completed, -outcome.DurationSeconds);
        end
    end
    [evidencePresent, outputHash, missing] = ...
        localRequiredEvidence(artifactIndex, item);
    passed = passed && evidencePresent;
    if ~evidencePresent
        failureCode = "FULLSTACK:RequiredSubcaseEvidenceMissing";
        details = "Missing/ambiguous required evidence: " + ...
            strjoin(missing, "|");
    elseif ~passed && strlength(failureCode) == 0
        failureCode = "FULLSTACK:SubcaseGateFailed";
    end
    rows(index) = struct( ...
        "RunID", char(ctx.RunID), ...
        "SubcaseID", char(item.SubcaseID), ...
        "ConfigurationRevisionID", char(ctx.ConfigurationRevisionID), ...
        "ResolvedYAMLSHA256", char(ctx.ResolvedYAMLSHA256), ...
        "ImplementationRegistrySHA256", char(implementationHash), ...
        "SeedSubstream", char(seedText), ...
        "Category", char(item.Category), ...
        "Mandatory", logical(item.Mandatory), ...
        "Executed", logical(executed), ...
        "StartedUTC", char(started), ...
        "CompletedUTC", char(completed), ...
        "Status", char(localStatus(passed)), ...
        "FailureCode", char(failureCode), ...
        "Details", char(details), ...
        "OutputManifestSHA256", char(outputHash));
end
T = struct2table(rows, "AsArray", true);
end

function [present, hash, missing] = localRequiredEvidence(artifactIndex, item)
names = [item.RequiredCSV(:); item.RequiredPNG(:)];
missing = strings(0,1);
bindings = strings(0,1);
for name = reshape(names,1,[])
    [path,uniquePath] = sixgr.integration.qualification. ...
        RunArtifactIndex.findUnique(artifactIndex,name);
    if ~uniquePath
        missing(end+1,1) = name; %#ok<AGROW>
        continue;
    end
    fileHash = sixgr.integration.qualification. ...
        FullStackRunContext.fileHash(path);
    bindings(end+1,1) = name + ":" + fileHash; %#ok<AGROW>
end
present = isempty(missing) && ~isempty(names);
if present
    bytes = uint8(unicode2native(char(strjoin(sort(bindings), newline)), ...
        "UTF-8"));
    hash = lower(string(sixgr.util.sha256Hex(bytes)));
else
    hash = "";
end
end

function tf = localRequiredPass(T)
tf = istable(T) && ~isempty(T) && ...
    ismember("Status", string(T.Properties.VariableNames));
if ~tf, return; end
mask = true(height(T),1);
if ismember("Required", string(T.Properties.VariableNames))
    mask = localTruth(T.Required);
elseif ismember("Mandatory", string(T.Properties.VariableNames))
    mask = localTruth(T.Mandatory);
end
tf = any(mask) && all(upper(string(T.Status(mask))) == "PASS");
end

function tf = localRegressionPass(T)
tf = istable(T) && height(T) == 10 && ...
    all(upper(string(T.Status)) == "PASS") && ...
    all(double(T.FailedTests) == 0) && ...
    all(double(T.SkippedTests) == 0) && ...
    all(double(T.BlockedTests) == 0);
end

function tf = localCausalityPass(T)
tf = istable(T) && ~isempty(T) && ...
    all(upper(string(T.Status)) == "PASS") && ...
    all(logical(T.TimeOrderValid)) && all(logical(T.IdentityValid));
end

function tf = localTruth(value)
if islogical(value) || isnumeric(value)
    tf = logical(value);
else
    tf = ismember(lower(strtrim(string(value))), ...
        ["true","1","yes","pass","required"]);
end
end

function value = localSpecial(s, name)
value = isfield(s, name) && logical(s.(name));
end

function value = localFailure(passed, code)
if passed, value = ""; else, value = string(code); end
end

function value = localStatus(passed)
if passed, value = "PASS"; else, value = "FAIL"; end
end

function value = localExitCode(passed)
if passed, value = 0; else, value = 2; end
end

function value = localUTC()
value = string(datetime("now","TimeZone","UTC", ...
    "Format","yyyy-MM-dd'T'HH:mm:ss.SSS'Z'"));
end

function value = localUTCOffset(utcText, offsetSeconds)
try
    instant = datetime(utcText, "TimeZone", "UTC", ...
        "InputFormat", "yyyy-MM-dd'T'HH:mm:ss.SSS'Z'");
    instant = instant + seconds(offsetSeconds);
    instant.Format = "yyyy-MM-dd'T'HH:mm:ss.SSS'Z'";
    value = string(instant);
catch
    value = string(utcText);
end
end

function row = localSubcaseRow()
row = struct("RunID","","SubcaseID","", ...
    "ConfigurationRevisionID","","ResolvedYAMLSHA256","", ...
    "ImplementationRegistrySHA256","","SeedSubstream","", ...
    "Category","","Mandatory",true,"Executed",false, ...
    "StartedUTC","","CompletedUTC","","Status","FAIL", ...
    "FailureCode","","Details","","OutputManifestSHA256","");
end
