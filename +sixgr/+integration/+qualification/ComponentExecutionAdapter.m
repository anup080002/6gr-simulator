classdef ComponentExecutionAdapter
    %COMPONENTEXECUTIONADAPTER Dispatch to existing production phase runners.
    methods (Static)
        function group = groupFor(subcaseID)
            switch string(subcaseID)
                case "SC-00", group = "PREFLIGHT";
                case "SC-01", group = "FRAME";
                case {"SC-02","SC-03"}, group = "WAVEFORM";
                case {"SC-04","SC-05"}, group = "FIXED_SWEEP";
                case "SC-06", group = "INITIAL_ACCESS";
                case "SC-07", group = "PDCCH";
                case "SC-08", group = "PDSCH";
                case "SC-09", group = "PUSCH";
                case "SC-10", group = "PUCCH";
                case {"SC-11","SC-12"}, group = "RSLA";
                case {"SC-13","SC-14"}, group = "MIMO";
                case {"SC-15","SC-16","SC-17","SC-18"}, group = "CHANNEL";
                case {"SC-19","SC-20","SC-21"}, group = "RF";
                case "SC-22", group = "MAC";
                case {"SC-23","SC-24","SC-25"}, group = "PROTOCOL";
                case "SC-26", group = "NEGATIVE";
                case "SC-27", group = "VALIDATION";
                case {"SC-28","SC-29"}, group = "ORCHESTRATOR";
                case "SC-30", group = "REGRESSION";
                otherwise
                    error("FULLSTACK:UnknownSubcase", ...
                        "No component execution group is mapped for %s.", subcaseID);
            end
        end

        function outcome = execute(group, ctx)
            group = upper(string(group));
            started = tic;
            outputDir = fullfile(ctx.EvidenceDir, lower(group));
            outcome = struct("Group",group,"Executed",false,"Passed",false, ...
                "FailureCode","","Details","","OutputDir",string(outputDir), ...
                "DurationSeconds",NaN,"Summary",struct());
            try
                if isfolder(outputDir)
                    error("FULLSTACK:StaleGroupOutput", ...
                        "Qualification group output must be fresh: %s", outputDir);
                end
                vectorRoot = fullfile(ctx.Profile.RepositoryRoot, ...
                    "tests", "vectors");
                seeds = double(sixgr.util.structGet( ...
                    ctx.Profile.PresetConfiguration, "fixed_snr_seeds", [11 23]));
                confidence = double(sixgr.util.structGet( ...
                    ctx.Profile.Configuration, ...
                    "validation.confidence_level", 0.95));
                switch group
                    case "PREFLIGHT"
                        sixgr.util.ensureFolder(outputDir);
                        summary = struct("Passed", ...
                            ctx.ResolvedYAMLSHA256 == ctx.ExecutedYAMLSHA256);
                    case "FRAME"
                        [manifest, testSummary] = runFrameGridPhaseTests(outputDir);
                        summary = struct("Passed",logical(manifest.AllStatusPass), ...
                            "Manifest",manifest,"TestSummary",testSummary);
                    case "WAVEFORM"
                        summary = sixgr.phy.waveform.runWaveformPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"waveform"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevel",confidence,"Strict",true);
                    case "FIXED_SWEEP"
                        summary = localRunFixedSweep(ctx, outputDir, seeds, confidence);
                    case "INITIAL_ACCESS"
                        summary = sixgr.phy.ia.runInitialAccessPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"initial_access"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevel",confidence,"Strict",true);
                    case "PDCCH"
                        summary = sixgr.phy.pdcch.runPDCCHPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"pdcch"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevel",confidence,"Strict",true, ...
                            "FastTestMode",false);
                    case "PDSCH"
                        summary = sixgr.pdsch.runPDSCHPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"pdsch"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevel",confidence,"Strict",true);
                    case "PUSCH"
                        summary = sixgr.phy.ul.pusch.runPUSCHPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"pusch"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevel",confidence,"Strict",true);
                    case "PUCCH"
                        summary = sixgr.phy.pucch.runPUCCHPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"pucch"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevel",confidence,"Strict",true, ...
                            "FastTestMode",false);
                    case "RSLA"
                        summary = sixgr.phy.rsla.runRSLAPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"rsla"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevel",confidence,"Strict",true);
                    case "MIMO"
                        summary = sixgr.phy.mimo. ...
                            runMIMOCSIBeamformingPhaseValidation( ...
                            VectorRoot=string(fullfile(vectorRoot,"mimo")), ...
                            OutputDir=string(outputDir),SeedList=seeds, ...
                            ConfidenceLevel=confidence,Strict=true);
                    case "CHANNEL"
                        summary = sixgr.channel.runtime. ...
                            runChannelGeometryPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"channel"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevel",confidence,"Strict",true);
                    case "RF"
                        summary = sixgr.rf.runtime.runRFFrontEndPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"rf"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevel",confidence,"Strict",true);
                    case "MAC"
                        summary = sixgr.l2.mac. ...
                            runMACHARQSchedulingPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"mac"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevel",confidence,"Strict",true);
                    case "PROTOCOL"
                        summary = sixgr.protocol.runProtocolStackPhaseValidation( ...
                            VectorRoot=string(fullfile(vectorRoot,"protocol")), ...
                            OutputDir=string(outputDir),SeedList=seeds, ...
                            ConfidenceLevel=confidence,Strict=true);
                    case "NEGATIVE"
                        sixgr.util.ensureFolder(outputDir);
                        summary = struct("Passed",true, ...
                            "Notes","Domain negative cases are bound by FullStackNegativeFaultExecutor.");
                    case "VALIDATION"
                        summary = sixgr.validation.runValidationPhaseValidation( ...
                            "VectorRoot",fullfile(vectorRoot,"validation"), ...
                            "OutputDir",outputDir,"SeedList",seeds, ...
                            "ConfidenceLevels",confidence,"Strict",true);
                    otherwise
                        error("FULLSTACK:InvalidExecutionGroup", ...
                            "Group %s is orchestrator-owned and cannot be dispatched.", group);
                end
                outcome.Executed = true;
                outcome.Passed = localPassed(summary);
                outcome.Summary = summary;
                if ~outcome.Passed
                    outcome.FailureCode = "FULLSTACK:" + group + "GateFailed";
                    outcome.Details = "Production runner returned a non-passing gate.";
                end
            catch ME
                outcome.Executed = true;
                outcome.Passed = false;
                outcome.FailureCode = string(ME.identifier);
                if strlength(outcome.FailureCode) == 0
                    outcome.FailureCode = "FULLSTACK:" + group + "ExecutionFailed";
                end
                outcome.Details = string(ME.message);
            end
            outcome.DurationSeconds = toc(started);
        end
    end
end

function summary = localRunFixedSweep(ctx, outputDir, seeds, confidence)
sixgr.util.ensureFolder(outputDir);
cfg = ctx.Config;
q = ctx.Profile.Configuration;
snr = double(sixgr.util.structGet(q, ...
    "main_fixed_sinr_sweep.snr_db", []));
mcsDL = double(sixgr.util.structGet(q, ...
    "main_fixed_sinr_sweep.fixed_mcs_dl", NaN));
mcsUL = double(sixgr.util.structGet(q, ...
    "main_fixed_sinr_sweep.fixed_mcs_ul", NaN));
rank = double(sixgr.util.structGet(q, ...
    "main_fixed_sinr_sweep.fixed_rank", NaN));
trials = double(sixgr.util.structGet( ...
    ctx.Profile.PresetConfiguration, ...
    "fixed_tbs_per_point_per_direction_per_seed", NaN));
if numel(snr) ~= 5 || ~isequal(snr(:).', [-8 -4 0 4 10]) || ...
        any(~isfinite([mcsDL,mcsUL,rank,trials]))
    error("FULLSTACK:FixedSweepConfigurationInvalid", ...
        "Fixed sweep must resolve the five contract SNRs and finite MCS/rank/trial counts.");
end
campaignCfg = struct( ...
    "Enabled",true,"FixedReferenceMode",true, ...
    "SingleUserMode",true,"ConfigurationAuthority","master_yaml", ...
    "Direction","both","ChannelModel","AWGN", ...
    "NoiseOperatingMode","standalone_awgn_snr_argument", ...
    "PDSCHExecutionProfile","phy_calibration", ...
    "LinkAdaptationMode","fixed","HARQEnabled",false, ...
    "SNR_dB",snr,"MCS",unique([mcsDL,mcsUL]), ...
    "Rank",rank,"Layers",rank,"NPRB", ...
    double(sixgr.util.structGet(q,"carrier.active_bwp_nrb",24)), ...
    "MinTBPerPoint",trials*numel(seeds), ...
    "MaxTBPerPoint",trials*numel(seeds), ...
    "MinErrorsForCI",0,"MaxCIHalfWidth",0.5, ...
    "BatchTBCount",trials,"TargetBLER",[0.1 0.01], ...
    "Seeds",seeds,"SeedBase",seeds(1), ...
    "ConfidenceLevel",confidence, ...
    "DisableAuxiliarySignals",false,"EnablePTRS",true);
opt = struct( ...
    "PersistenceEnabled",true, ...
    "FixedLinkCampaignOnly",true, ...
    "LinkSNR_dB",0, ...
    "LinkSNRGrid_dB",snr, ...
    "LinkMaxSimFrames",trials, ...
    "LinkSweepFrames",1, ...
    "LinkSweepTrialsPerSNR",trials*numel(seeds), ...
    "LinkSweepMaxPoints",5, ...
    "LinkFixedLinkCampaignEnabled",true, ...
    "LinkFixedLinkCampaignConfig",campaignCfg, ...
    "LinkFixedLinkSNRGrid_dB",snr, ...
    "SaveFigures",true);
cfg = sixgr.util.structSet(cfg, "run.rootRunFolder", outputDir);
out = sixgr.truth.runWaveformLinkBundle(cfg, ...
    fullfile(outputDir,"air_interface"), opt);
campaign = sixgr.util.structGet(out, "FixedLinkCampaign", struct());
curve = localConsolidateCurves(ctx.RunID, campaign);
if isempty(curve)
    error("FULLSTACK:FixedSweepEvidenceMissing", ...
        "The production fixed-link campaign returned no DL/UL BLER curve.");
end
sixgr.util.csvWriteTable(fullfile(outputDir, ...
    "fixed_snr_bler_curve.csv"), curve);
summary = struct("Passed",logical(sixgr.util.structGet(out,"Ok",false)), ...
    "Output",out,"Curve",curve);
end

function T = localConsolidateCurves(runID, campaign)
T = table();
for direction = ["DL","UL"]
    curve = sixgr.util.structGet(campaign, ...
        direction + "BlerCurve", table());
    if ~(istable(curve) && ~isempty(curve))
        continue;
    end
    n = height(curve);
    pointStatus = repmat("PASS", n, 1);
    if ismember("Incomplete", string(curve.Properties.VariableNames))
        pointStatus(logical(curve.Incomplete)) = "FAIL";
    end
    status = pointStatus;
    part = table(repmat(string(runID),n,1), ...
        repmat(direction,n,1), double(curve.MCSIndex), ...
        double(curve.ConfiguredRank), double(curve.SNR_dB), ...
        double(curve.TrialCount), double(curve.FailureCount), ...
        double(curve.Value), double(curve.CI_Low), ...
        double(curve.CI_High), pointStatus, status, ...
        'VariableNames', {'RunID','Direction','MCS','Rank', ...
        'ConfiguredSNR_dB','Trials','Errors','BLER', ...
        'CILower','CIUpper','PointStatus','Status'});
    if isempty(T), T = part; else, T = [T;part]; end %#ok<AGROW>
end
end

function passed = localPassed(summary)
passed = true;
if isstruct(summary)
    for field = ["Passed","Ok","AllStatusPass"]
        if isfield(summary, field)
            value = summary.(field);
            if islogical(value) || isnumeric(value)
                passed = logical(value(1));
                return;
            end
        end
    end
end
end
