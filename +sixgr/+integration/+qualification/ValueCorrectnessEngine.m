classdef ValueCorrectnessEngine
    %VALUECORRECTNESSENGINE Canonical typed Phase-18 value evaluation.
    methods (Static)
        function [results,trace,resolutionTrace,adapterResults] = ...
                evaluate(ctx)
            resolver = sixgr.integration.qualification. ...
                ArtifactResolver.create(ctx.RunFolder,ctx.Profile);
            [results,trace,resolutionTrace,adapterResults] = ...
                sixgr.integration.qualification. ...
                MultiSourceValueEvaluator.evaluate( ...
                ctx.Profile.ValueChecks,resolver,ctx.RunID,true);
            sixgr.util.csvWriteTable(fullfile(ctx.CSVDir, ...
                "full_stack_value_correctness_results.csv"),results);
            sixgr.util.csvWriteTable(fullfile(ctx.CSVDir, ...
                "phase18_value_evaluation_trace.csv"),trace);
            sixgr.util.csvWriteTable(fullfile(ctx.CSVDir, ...
                "phase18_artifact_resolution_trace.csv"), ...
                resolutionTrace);
            sixgr.util.csvWriteTable(fullfile(ctx.CSVDir, ...
                "phase18_schema_adapter_results.csv"),adapterResults);
        end
    end
end
