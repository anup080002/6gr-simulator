classdef QualificationFinalizationCoordinator
    %QUALIFICATIONFINALIZATIONCOORDINATOR Explicit finalization state machine.
    methods (Static)
        function result = assess(subcases,values,components,audit, ...
                publication,regression,acceptance)
            [audit,schemaDiagnostic] = sixgr.integration.qualification. ...
                QualificationArtifactAuditNormalizer.normalize(audit);
            stages = ["DOMAIN_RUNS_COMPLETE"; ...
                "DOMAIN_EXPORTERS_COMPLETE"; ...
                "NEGATIVE_TESTS_COMPLETE"; ...
                "VALUE_CHECKS_COMPLETE"; ...
                "COMPONENT_REDUCTION_COMPLETE"; ...
                "SUBCASE_REDUCTION_COMPLETE"; ...
                "PLOTS_COMPLETE"; ...
                "ARTIFACT_INDEX_COMPLETE"; ...
                "ARTIFACT_HASHES_FINAL"; ...
                "WEBGUI_PUBLICATION_COMPLETE"; ...
                "REGRESSION_COMPLETE"; ...
                "FINAL_ACCEPTANCE_COMPLETE"];
            complete = false(numel(stages),1);
            detail = strings(numel(stages),1);
            complete(1) = all(localTruth(subcases.Executed( ...
                string(subcases.SubcaseID)~="SC-30")));
            detail(1) = "All non-regression source subcases report execution.";
            schemaReady = string(schemaDiagnostic.Status)=="PASS";
            complete(2) = schemaReady && ~isempty(audit) && ...
                all(audit.Present | ...
                ~localTruth(localRequiredColumn(audit,"RequiredForPreset", ...
                audit.Required)));
            detail(2) = localSchemaDetail(schemaDiagnostic, ...
                "Required domain exporters are represented by files.");
            complete(3) = true;
            detail(3) = "Negative ledger was loaded before reduction.";
            complete(4) = height(values)==107;
            detail(4) = "All 107 value rules have typed results.";
            complete(5) = height(components)==163;
            detail(5) = "All 163 components were reduced.";
            complete(6) = height(subcases)==31;
            detail(6) = "All 31 subcases were reduced.";
            png = string(audit.ArtifactType)=="PNG";
            requiredPNG = png & audit.Required;
            complete(7) = schemaReady && any(requiredPNG) && ...
                all(audit.Present(requiredPNG));
            detail(7) = "Every required PNG exists.";
            complete(8) = height(audit)>0 && ...
                ismember("SHA256",string(audit.Properties.VariableNames)) && ...
                all(strlength(string(audit.SHA256(audit.Present)))==64);
            detail(8) = "Actual artifact index contains current SHA-256 values.";
            complete(9) = complete(8) && ...
                ismember("HashValid",string(audit.Properties.VariableNames)) && ...
                all(audit.HashValid(audit.Present));
            detail(9) = "All present artifacts have verified final hashes.";
            complete(10) = ~isempty(publication) && ...
                all(string(publication.Status)=="PASS");
            detail(10) = "Required WebGUI publication rows pass.";
            complete(11) = ~isempty(regression) && ...
                all(string(regression.Status)=="PASS") && ...
                all(double(regression.BlockedTests)==0) && ...
                all(double(regression.SkippedTests)==0);
            detail(11) = "All sharded regression suites completed.";
            complete(12) = height(acceptance)==387 && ...
                all(string(acceptance.Status( ...
                localTruth(acceptance.Required)))=="PASS");
            detail(12) = "All required acceptance rules pass.";

            state = repmat("BLOCKED",numel(stages),1);
            gateOpen = true;
            for index=1:numel(stages)
                if gateOpen && complete(index)
                    state(index)="COMPLETE";
                elseif gateOpen
                    state(index)="INCOMPLETE";
                    gateOpen=false;
                end
            end
            stageTable=table(stages,state,complete,detail, ...
                'VariableNames',{'Stage','State','ConditionSatisfied', ...
                'Details'});
            interrupted = false;
            if ~complete(11) && ~isempty(regression) && ...
                    all(ismember(["BlockedTests","ExecutedTests"], ...
                    string(regression.Properties.VariableNames)))
                interrupted = any(double(regression.BlockedTests)>0 | ...
                    double(regression.ExecutedTests)==0);
            end
            if interrupted
                finalStatus="INTERRUPTED";
            elseif all(complete)
                finalStatus="PASS";
            else
                finalStatus="FAIL";
            end
            result=struct("Stages",stageTable,"FinalStatus",finalStatus, ...
                "FinalManifestComplete",all(complete), ...
                "PublicationComplete",complete(10)&&all(complete(1:9)), ...
                "RegressionComplete",complete(11), ...
                "ArtifactSchemaDiagnostic",schemaDiagnostic, ...
                "CanonicalArtifactAudit",audit);
        end

        function assertCanWriteFinalManifest(result)
            if ~result.FinalManifestComplete
                error("FULLSTACK:FinalizationIncomplete", ...
                    "A final manifest cannot be written before every stage completes.");
            end
        end
    end
end

function detail=localSchemaDetail(diagnostic,passDetail)
if string(diagnostic.Status)=="PASS"
    detail=string(passDetail);
else
    detail=string(diagnostic.FailureCode)+": "+string(diagnostic.Details);
end
end

function value=localRequiredColumn(T,name,fallback)
if ismember(name,string(T.Properties.VariableNames))
    value=T.(char(name));
else
    value=fallback;
end
end

function tf=localTruth(value)
tf=ismember(lower(strtrim(string(value))), ...
    ["true","1","yes","pass","required"]);
end
