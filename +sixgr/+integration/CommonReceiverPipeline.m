classdef CommonReceiverPipeline
    %COMMONRECEIVERPIPELINE Shared synchronization/demodulation decision floor.
    methods (Static)
        function result = recover(received,clean,noise,nfft,cp,nOccupied,bits)
            symbols = numel(cp);
            [grid,info] = sixgr.phy.waveform.CanonicalOFDMDemodulator.math( ...
                received,nfft,cp,nOccupied);
            cleanGrid = sixgr.phy.waveform.CanonicalOFDMDemodulator.math( ...
                clean,nfft,cp,nOccupied);
            noiseGrid = sixgr.phy.waveform.CanonicalOFDMDemodulator.math( ...
                noise,nfft,cp,nOccupied);
            decoded = zeros(2*numel(grid),1);
            decoded(1:2:end) = real(grid(:)) < 0;
            decoded(2:2:end) = imag(grid(:)) < 0;
            decoded = decoded(1:numel(bits));
            bitErrors = sum(decoded ~= bits(:));
            errorGrid = grid-cleanGrid;
            postSINR = 10*log10(sum(abs(cleanGrid(:)).^2)/ ...
                max(sum(abs(errorGrid(:)).^2),realmin));
            result = struct("Grid",grid,"CleanGrid",cleanGrid, ...
                "NoiseGrid",noiseGrid,"DecodedBits",decoded, ...
                "BitErrors",bitErrors,"BER",bitErrors/numel(bits), ...
                "PostEqualizationSINR_dB",postSINR, ...
                "GridNMSE",sum(abs(errorGrid(:)).^2)/ ...
                max(sum(abs(cleanGrid(:)).^2),realmin), ...
                "GridSHA256",sixgr.integration.IntegrationHash.data( ...
                localComplex(grid)),"ReceiverResultSHA256", ...
                sixgr.integration.IntegrationHash.data(struct( ...
                "DecodedBits",decoded.',"Grid",localComplex(grid), ...
                "PostSINR",postSINR,"Symbols",symbols)), ...
                "ImplementationSHA256",sixgr.integration.IntegrationHash.file( ...
                which("sixgr.integration.CommonReceiverPipeline")), ...
                "OFDMInfo",info);
        end
    end
end

function value = localComplex(input)
value = struct("Real",real(double(input(:))).', ...
    "Imag",imag(double(input(:))).',"Size",size(input));
end
