function out = runPhase7ExecutionEvidence(cfg, runFolder, varargin)
%RUNPHASE7EXECUTIONEVIDENCE Execute real resume and determinism validations.
%
% This validator never derives publication statistics.  It executes a
% bounded subset of the production waveform chains solely to prove that a
% fixed-link campaign resumes from an identity-bound point checkpoint and
% that FRC transport blocks are invariant to serial/parallel scheduling.

ip = inputParser;
ip.addRequired("cfg", @(x)isstruct(x) && isscalar(x));
ip.addRequired("runFolder", @(x)ischar(x) || isstring(x));
ip.addParameter("Config", struct(), @(x)isstruct(x) && isscalar(x));
ip.addParameter("WriteArtifacts", true, @(x)islogical(x) || (isnumeric(x) && isscalar(x)));
ip.parse(cfg, runFolder, varargin{:});
opt = ip.Results;

validationCfg = localResolveConfig(cfg, opt.Config);
layout = sixgr.report.resultLayout(runFolder);
checkpointT = localCheckpointResumeEvidence(cfg, validationCfg, layout);
determinismT = localSerialParallelEvidence(validationCfg);

if logical(opt.WriteArtifacts)
    sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, ...
        "checkpoint_resume_equivalence.csv"), checkpointT);
    sixgr.util.csvWriteTable(fullfile(layout.ReportCSVDir, ...
        "serial_parallel_determinism.csv"), determinismT);
end

out = struct( ...
    "Enabled", logical(validationCfg.Enabled), ...
    "CheckpointResume", checkpointT, ...
    "SerialParallel", determinismT, ...
    "CheckpointResumeEquivalenceOk", localTablePass(checkpointT, ...
        "CheckpointResumeEquivalenceOk"), ...
    "SerialParallelDeterminismOk", localTablePass(determinismT, ...
        "SerialParallelDeterminismOk"));
out.AllPassed = out.CheckpointResumeEquivalenceOk && ...
    out.SerialParallelDeterminismOk;
end

function validationCfg = localResolveConfig(cfg, overlay)
validationCfg = sixgr.util.structGet(cfg, ...
    "validation.phase7_execution_validation", struct());
if isstruct(overlay) && isscalar(overlay)
    names = fieldnames(overlay);
    for i = 1:numel(names)
        validationCfg.(names{i}) = overlay.(names{i});
    end
end
validationCfg.Enabled = logical(sixgr.util.structGet(validationCfg, ...
    "Enabled", sixgr.util.structGet(validationCfg, "enabled", false)));
validationCfg.CheckpointResume = sixgr.util.structGet(validationCfg, ...
    "CheckpointResume", sixgr.util.structGet(validationCfg, ...
    "checkpoint_resume", struct()));
validationCfg.SerialParallel = sixgr.util.structGet(validationCfg, ...
    "SerialParallel", sixgr.util.structGet(validationCfg, ...
    "serial_parallel", struct()));
end

function T = localCheckpointResumeEvidence(cfg, validationCfg, layout)
enabled = logical(validationCfg.Enabled) && logical(sixgr.util.structGet( ...
    validationCfg.CheckpointResume, "enabled", true));
if ~enabled
    T = localCheckpointRow(false, "NOT_EVALUATED", "validation_disabled", ...
        "", "", 0, 0, 0, 0, "", "");
    return;
end

checkpointPath = fullfile(layout.MetaDir, ...
    "phase7_fixed_link_resume_checkpoint.mat");
try
    campaignCfg = localBoundedCampaignConfig(cfg, ...
        validationCfg.CheckpointResume);
    baseline = sixgr.lls6g.campaign.runFixedLinkCampaign(cfg, ...
        "Config", campaignCfg, "WriteArtifacts", false);
    partial = sixgr.lls6g.campaign.runFixedLinkCampaign(cfg, ...
        "Config", campaignCfg, "WriteArtifacts", false, ...
        "CheckpointPath", checkpointPath, ...
        "MaxPointsThisInvocation", 1);
    resumed = sixgr.lls6g.campaign.runFixedLinkCampaign(cfg, ...
        "Config", campaignCfg, "WriteArtifacts", false, ...
        "CheckpointPath", checkpointPath, ...
        "ResumeFromCheckpoint", true);

    [ok, baselineHash, resumedHash] = localCampaignEqual(baseline, resumed);
    partialOk = ~logical(sixgr.util.structGet(partial, "Completed", true)) && ...
        double(sixgr.util.structGet(partial, "CompletedPointCount", 0)) == 1;
    resumedOk = logical(sixgr.util.structGet(resumed, "Completed", false)) && ...
        logical(sixgr.util.structGet(resumed, "ResumedFromCheckpoint", false));
    ok = ok && partialOk && resumedOk;
    status = localPassStatus(ok);
    reason = "";
    if ~ok
        reason = "resumed_campaign_differs_from_uninterrupted_campaign";
    end
    T = localCheckpointRow(ok, status, reason, baselineHash, resumedHash, ...
        height(baseline.Summary), height(resumed.Summary), ...
        height(baseline.DLTrials) + height(baseline.ULTrials), ...
        height(resumed.DLTrials) + height(resumed.ULTrials), ...
        string(baseline.CampaignIdentity), string(resumed.CampaignIdentity));
catch ME
    T = localCheckpointRow(false, "FAIL", string(ME.identifier) + ":" + ...
        string(ME.message), "", "", 0, 0, 0, 0, "", "");
end
end

function T = localSerialParallelEvidence(validationCfg)
enabled = logical(validationCfg.Enabled) && logical(sixgr.util.structGet( ...
    validationCfg.SerialParallel, "enabled", true));
if ~enabled
    T = localDeterminismRow(false, "NOT_EVALUATED", ...
        "validation_disabled", "", "", 0, 0, 0, "");
    return;
end

detCfg = validationCfg.SerialParallel;
entryId = string(sixgr.util.structGet(detCfg, "frc_entry_id", ...
    "dl_r_pdsch_1_1_4_fdd_awgn"));
conditionId = string(sixgr.util.structGet(detCfg, "condition_id", ...
    "awgn_static_1x2"));
tbCount = max(2, round(double(sixgr.util.structGet(detCfg, ...
    "transport_blocks", 2))));
workers = max(2, round(double(sixgr.util.structGet(detCfg, ...
    "parallel_workers", 2))));
seed = round(double(sixgr.util.structGet(detCfg, "seed", 38104)));
args = {"ExecutionProfile","full", ...
    "EvaluateSymmetricRegression",false, ...
    "MinTransportBlocks",tbCount,"MaxTransportBlocks",tbCount, ...
    "BatchSize",tbCount,"MinimumBlockErrors",0,"Seed",seed, ...
    "PrintTable",false,"Verbose",false};
try
    serial = sixgr.conformance.runFRCPoint(entryId, conditionId, ...
        args{:}, "ParallelWorkers", 0);
    parallel = sixgr.conformance.runFRCPoint(entryId, conditionId, ...
        args{:}, "ParallelWorkers", workers);
    [ok, serialHash, parallelHash, comparedRows] = ...
        localFRCEqual(serial, parallel);
    reason = "";
    if ~ok
        reason = "serial_parallel_frc_truth_differs";
    end
    T = localDeterminismRow(ok, localPassStatus(ok), reason, ...
        serialHash, parallelHash, comparedRows, workers, tbCount, entryId);
catch ME
    T = localDeterminismRow(false, "FAIL", string(ME.identifier) + ":" + ...
        string(ME.message), "", "", 0, workers, tbCount, entryId);
end
end

function campaignCfg = localBoundedCampaignConfig(cfg, checkCfg)
campaignCfg = sixgr.util.structGet(cfg, ...
    "validation.fixed_link_campaign", struct());
snr = double(sixgr.util.structGet(checkCfg, "snr_db", [10 20]));
snr = snr(isfinite(snr));
if numel(snr) < 2
    error("sixgr:validation:Phase7ResumeNeedsTwoPoints", ...
        "Checkpoint/resume validation requires at least two finite SNR points.");
end
mcs = double(sixgr.util.structGet(checkCfg, "mcs", ...
    sixgr.util.structGet(campaignCfg, "mcs", 0)));
tbCount = max(1, round(double(sixgr.util.structGet(checkCfg, ...
    "transport_blocks_per_point", 1))));
campaignCfg.enabled = true;
campaignCfg.direction = char(upper(string(sixgr.util.structGet(checkCfg, ...
    "direction", "DL"))));
campaignCfg.snr_db = reshape(snr(1:2), 1, []);
campaignCfg.mcs = reshape(mcs(1), 1, []);
campaignCfg.min_tb_per_point = tbCount;
campaignCfg.max_tb_per_point = tbCount;
campaignCfg.min_errors_for_ci = 0;
campaignCfg.max_ci_half_width = 1;
campaignCfg.trials_per_drop = tbCount;
% Resume currently persists complete points and therefore executes in a
% deterministic serial topology.  Compare like-for-like here; independent
% serial/parallel equivalence is evaluated by the dedicated FRC gate.
campaignCfg.parallel_workers = 0;
end

function [ok, baselineHash, resumedHash] = localCampaignEqual(a, b)
fields = ["Summary","DLTrials","ULTrials","TaskPlan"];
ok = true;
for field = fields
    ok = ok && isequaln(localScientificTable(a.(char(field))), ...
        localScientificTable(b.(char(field))));
end
baselineHash = localHashCampaign(a);
resumedHash = localHashCampaign(b);
ok = ok && baselineHash == resumedHash;
end

function hash = localHashCampaign(campaign)
payload = struct("Summary", table2struct(localScientificTable(campaign.Summary)), ...
    "DLTrials", table2struct(localScientificTable(campaign.DLTrials)), ...
    "ULTrials", table2struct(localScientificTable(campaign.ULTrials)), ...
    "TaskPlan", table2struct(localScientificTable(campaign.TaskPlan)));
hash = string(sixgr.util.sha256Hex(uint8(unicode2native( ...
    jsonencode(payload), "UTF-8"))));
end

function T = localScientificTable(T)
% Decoder latency is an observed wall-clock performance metric.  It is
% intentionally retained in campaign output and performance reports, but
% cannot be bit-identical across two executions.  Physics, bits, seeds,
% grants, channel samples, SINR, errors, and all other columns remain in the
% equality/hash contract.
if ~istable(T)
    return;
end
excluded = intersect(string(T.Properties.VariableNames), ...
    ["DecodeLatency_ms","DL_DecodeLatency_ms","UL_DecodeLatency_ms", ...
    "ComputeLatency_ms","ReceiverPipelineLatency_ms"], ...
    "stable");
if ~isempty(excluded)
    T(:, cellstr(excluded)) = [];
end
end

function [ok, serialHash, parallelHash, comparedRows] = localFRCEqual(a, b)
da = a.PointDetails{1};
db = b.PointDetails{1};
aa = da.TransportBlockAudit;
ab = db.TransportBlockAudit;
ok = isequaln(a.Sweep, b.Sweep) && ...
    isequaln(aa.Delivered, ab.Delivered) && ...
    isequaln(aa.Attempts, ab.Attempts) && ...
    isequaln(aa.NoiseSeedByAttempt, ab.NoiseSeedByAttempt) && ...
    isequaln(aa.RVByAttempt, ab.RVByAttempt) && ...
    isequaln(aa.AbsoluteSlotByAttempt, ab.AbsoluteSlotByAttempt) && ...
    isequaln(aa.ChannelStartSampleByAttempt, ab.ChannelStartSampleByAttempt) && ...
    isequaln(da.FirstTransmission, db.FirstTransmission) && ...
    isequaln(da.LastReceiver, db.LastReceiver) && ...
    logical(db.ParallelExecution) && double(db.ParallelPoolWorkers) >= 2;
serialHash = localHashFRC(a);
parallelHash = localHashFRC(b);
ok = ok && serialHash == parallelHash;
comparedRows = height(a.Sweep) + numel(aa.Delivered) + ...
    numel(aa.NoiseSeedByAttempt);
end

function hash = localHashFRC(result)
detail = result.PointDetails{1};
audit = detail.TransportBlockAudit;
payload = struct("Sweep", table2struct(result.Sweep), ...
    "Delivered", audit.Delivered, "Attempts", audit.Attempts, ...
    "NoiseSeedByAttempt", audit.NoiseSeedByAttempt, ...
    "RVByAttempt", audit.RVByAttempt, ...
    "AbsoluteSlotByAttempt", audit.AbsoluteSlotByAttempt, ...
    "ChannelStartSampleByAttempt", audit.ChannelStartSampleByAttempt, ...
    "FirstTransmission", detail.FirstTransmission, ...
    "LastReceiver", detail.LastReceiver);
hash = string(sixgr.util.sha256Hex(uint8(unicode2native( ...
    jsonencode(payload), "UTF-8"))));
end

function T = localCheckpointRow(ok, status, reason, baselineHash, resumedHash, ...
        baselinePoints, resumedPoints, baselineTrials, resumedTrials, ...
        baselineIdentity, resumedIdentity)
T = table(logical(ok), string(status), string(reason), ...
    "actual_fixed_link_waveform_point_checkpoint", ...
    string(baselineHash), string(resumedHash), ...
    double(baselinePoints), double(resumedPoints), ...
    double(baselineTrials), double(resumedTrials), ...
    string(baselineIdentity), string(resumedIdentity), ...
    "DecodeLatency_ms|DL_DecodeLatency_ms|UL_DecodeLatency_ms|ComputeLatency_ms|ReceiverPipelineLatency_ms", ...
    'VariableNames', {'CheckpointResumeEquivalenceOk','EvidenceStatus', ...
    'FailureReason','EvidenceSource','UninterruptedSHA256','ResumedSHA256', ...
    'UninterruptedPointCount','ResumedPointCount', ...
    'UninterruptedTrialCount','ResumedTrialCount', ...
    'UninterruptedCampaignIdentity','ResumedCampaignIdentity', ...
    'ExcludedNondeterministicPerformanceColumns'});
end

function T = localDeterminismRow(ok, status, reason, serialHash, ...
        parallelHash, comparedRows, workers, tbCount, entryId)
T = table(logical(ok), string(status), string(reason), ...
    "actual_frc_waveform_serial_parallel", string(serialHash), ...
    string(parallelHash), double(comparedRows), double(workers), ...
    double(tbCount), string(entryId), ...
    'VariableNames', {'SerialParallelDeterminismOk','EvidenceStatus', ...
    'FailureReason','EvidenceSource','SerialSHA256','ParallelSHA256', ...
    'ComparedValueCount','ParallelWorkers','TransportBlockCount','FRCEntryId'});
end

function status = localPassStatus(ok)
if ok
    status = "PASS";
else
    status = "FAIL";
end
end

function tf = localTablePass(T, columnName)
tf = istable(T) && height(T) == 1 && ...
    ismember(columnName, string(T.Properties.VariableNames)) && ...
    logical(T.(char(columnName))(1));
end
