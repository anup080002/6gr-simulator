function plan=preflightN40IntegrationGate(configPath,outputRoot,runTag)
% Validate both dispatched children before starting either expensive waveform.
requestedRoot=string(sixgr.util.canonicalPath(outputRoot));
resolvedRoot=string(sixgr.util.canonicalPath(sixgr.report.resolveResultsRoot(outputRoot)));
assert(strcmpi(requestedRoot,resolvedRoot),'sixgr:validation:N40GateOutputRoot', ...
    'Production storage policy redirects the requested output root. Configure SIXGR_RESULTS_ROOT explicitly before qualification.');
scfg=sixgr.lls6g.config.loadScenarioConfig(configPath);
data=scfg.toStruct();
assert(string(scfg.get('scenario.runner_profile'))=="generic_sweep" && ...
    string(scfg.get('scenario.sweep.base_profile'))=="waveform_bundle" && ...
    string(scfg.get('output.backend'))=="filesystem", ...
    'sixgr:validation:N40GateScenario','Require the filesystem waveform sweep.');
assert(isempty(getenv('SIXGR_OUTPUT_BACKEND_OVERRIDE')), ...
    'sixgr:validation:N40GateEnvironment','Remove the backend environment override before qualification.');
assert(~isempty(regexp(char(string(runTag)),'^[a-z0-9]+(_[a-z0-9]+)*$','once')), ...
    'sixgr:validation:N40GateRunTag','Use a new lowercase alphanumeric/underscore run tag without normalization.');
[~,rootLeaf]=fileparts(resolvedRoot);
assert(~any(strcmpi(string(rootLeaf),["lls",string(scfg.ScenarioID)])), ...
    'sixgr:validation:N40GateOutputRoot','Pass the base evidence root, not a bucket/profile subdirectory.');
folder=string(fullfile(resolvedRoot,'lls',scfg.ScenarioID,runTag));
assert(~isfolder(folder)&&~isfile(folder), ...
    'sixgr:validation:N40GateExistingRun','Qualification must never clean or overwrite an existing run.');
criteriaPath=fullfile(fileparts(fileparts(fileparts(mfilename('fullpath')))), ...
    'simulator','configs','validation','n40_integration_gate.yaml');
criteria=sixgr.lls6g.config.readConfigFile(criteriaPath);
window=double([criteria.continuation_start_slot criteria.checkpoint_slot criteria.completed_slots]);
assert(all(isfinite(window))&&all(window==fix(window))&&window(1)>0&& ...
    window(1)<window(2)&&window(2)==window(3), ...
    'sixgr:validation:N40GateCriteria','Require an earlier continuation checkpoint and the terminal required checkpoint.');
overrides=data.scenario.sweep.overrides;
if iscell(overrides), overrides=[overrides{:}]; end
assert(numel(overrides)==numel(criteria.sweep_labels), ...
    'sixgr:validation:N40GateChildren','Unexpected sweep population.');
children=struct([]);
for k=1:numel(overrides)
    label=string(overrides(k).label);
    child=sixgr.util.mergeStruct(data,overrides(k).config);
    child=sixgr.lls6g.config.normalizeScenarioAliases(child, ...
        'SourceFiles',scfg.SourceFiles,'ConfigPath',scfg.ConfigPath,'Authority',overrides(k).config);
    child.scenario.runner_profile='waveform_bundle';
    sixgr.lls6g.config.validateScenarioConfig(child,'Kind','scenario','AllowPartial',false);
    childScfg=sixgr.lls6g.config.ScenarioConfig(child,'SourceFiles',scfg.SourceFiles, ...
        'ConfigPath',scfg.ConfigPath,'ConfigHash',sixgr.lls6g.config.hashResolvedScenario(child),'Kind','scenario');
    cfg=sixgr.lls6g.buildInternalConfig(childScfg,fullfile(folder,'sweeps',label));
    assert(label==string(criteria.sweep_labels{k}) && ...
        child.simulation.snr_db==criteria.sweep_snr_db(k) && ...
        cfg.run.totalSlots==criteria.completed_slots && cfg.run.measurementSlots==criteria.completed_slots, ...
        'sixgr:validation:N40GateChildren','Require both ordered scenarios at the configured terminal horizon.');
    slots=1:cfg.run.totalSlots;
    due=arrayfun(@(slot)sixgr.runtime.CheckpointSchedule.due(slot, ...
        cfg.run.checkpointEverySlots,cfg.run.checkpointFirstSlot),slots);
    assert(cfg.run.runtimeCheckpointEnabled && isequal(slots(due),[criteria.continuation_start_slot criteria.checkpoint_slot]) && ...
        child.run_control.runtime_checkpoint_keep>=3, ...
        'sixgr:validation:N40GateCheckpoints','Retain the original continuation and terminal checkpoints plus the resumed endpoint.');
    item=struct('Label',label,'ScenarioID',childScfg.ScenarioID, ...
        'ConfigHash',childScfg.ConfigHash,'SNRdB',child.simulation.snr_db, ...
        'CompletedSlotsRequired',cfg.run.totalSlots,'CheckpointSlots',slots(due));
    children=[children;item]; %#ok<AGROW>
end
plan=struct('ContractVersion',"sixgr.n40.integration_gate_launch/v1", ...
    'ConfigPath',string(scfg.ConfigPath),'ConfigHash',string(scfg.ConfigHash), ...
    'SourceFiles',scfg.SourceFiles,'ResultsRoot',resolvedRoot,'RunFolder',folder,'RunTag',string(runTag), ...
    'CriteriaPath',string(criteriaPath),'CriteriaSHA256',sixgr.util.sha256File(criteriaPath), ...
    'ContinuationStartSlot',criteria.continuation_start_slot,'RequiredCheckpointSlot',criteria.checkpoint_slot, ...
    'FinalSlot',criteria.completed_slots, ...
    'Children',children,'PhysicalExecution',false);
end
