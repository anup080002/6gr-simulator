classdef MeasuredSINRGate
    %MEASUREDSINRGATE Receiver-derived measured SINR authority.
    methods (Static)
        function result=validate(measuredSINR,provenance,sampleCount,runClass,configuredSNR)
            if nargin>=4, sixgr.validation.RunClass.parse(runClass); end
            if isempty(measuredSINR) || (isstring(measuredSINR)&& ...
                    (ismissing(measuredSINR)||strlength(measuredSINR)==0))
                error("sixgr:validation:MeasuredSINRMissing", ...
                    "Measured SINR is mandatory for this run class.");
            end
            if isnumeric(measuredSINR) && isscalar(measuredSINR) && ...
                    isnan(double(measuredSINR)) && nargin >= 5 && ...
                    isnumeric(configuredSNR) && isscalar(configuredSNR) && ...
                    isfinite(double(configuredSNR))
                error("sixgr:validation:MeasuredSINRMissing", ...
                    "Measured SINR is mandatory for this run class.");
            end
            if ~(isnumeric(measuredSINR)&&isscalar(measuredSINR)&& ...
                    isfinite(double(measuredSINR)))
                error("sixgr:validation:SchemaNonFinite", ...
                    "Measured SINR must be a finite scalar.");
            end
            if ~sixgr.validation.EvidenceProvenanceClass.qualifiesRuntime(provenance)
                error("sixgr:validation:MeasuredSINRInvalidProvenance", ...
                    "Measured SINR is not receiver-derived runtime evidence.");
            end
            if ~(isnumeric(sampleCount)&&isscalar(sampleCount)&& ...
                    isfinite(sampleCount)&&sampleCount>=1&&sampleCount==fix(sampleCount))
                error("sixgr:validation:MeasuredSINRMissing", ...
                    "Measured SINR requires a positive sample count.");
            end
            result=struct("MeasuredSINR_dB",double(measuredSINR), ...
                "ProvenanceClass", ...
                sixgr.validation.EvidenceProvenanceClass.parse(provenance), ...
                "SampleCount",double(sampleCount),"Status","PASS");
        end
    end
end
