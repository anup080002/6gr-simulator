classdef SequentialDesign
    %SEQUENTIALDESIGN Predeclared bounded Bonferroni look design.
    methods (Static)
        function out = fromProfile(profile)
            if isa(profile,"sixgr.validation.ValidationPlanningResult")
                profile = profile.toStruct();
            end
            required = ["MinTrials","MinErrors","MaxTrials","MaxLooks", ...
                "LookSchedule","TargetHalfWidth", ...
                "TargetZeroErrorUpperBound","NominalConfidenceLevel"];
            if ~(isstruct(profile)&&isscalar(profile)) || ...
                    any(~isfield(profile,required))
                error("sixgr:validation:InvalidSequentialDesign", ...
                    "Sequential design input is incomplete.");
            end
            alpha = 1-double(profile.NominalConfidenceLevel);
            maxLooks = double(profile.MaxLooks);
            if ~(isfinite(maxLooks)&&maxLooks>=1&&maxLooks==fix(maxLooks))
                error("sixgr:validation:InvalidSequentialDesign", ...
                    "MaxLooks must be a positive integer.");
            end
            alphaPerLook = alpha/maxLooks;
            out = struct( ...
                "DesignID","BONFERRONI_BOUNDED_" + string(maxLooks), ...
                "MinTrials",double(profile.MinTrials), ...
                "MinErrors",double(profile.MinErrors), ...
                "MaxTrials",double(profile.MaxTrials), ...
                "MaxLooks",maxLooks, ...
                "LookSchedule",reshape(double(profile.LookSchedule),1,[]), ...
                "TargetHalfWidth",double(profile.TargetHalfWidth), ...
                "TargetZeroErrorUpperBound", ...
                    double(profile.TargetZeroErrorUpperBound), ...
                "NominalConfidenceLevel",double(profile.NominalConfidenceLevel), ...
                "NominalAlpha",alpha,"AlphaPerLook",alphaPerLook, ...
                "LookConfidenceLevel",1-alphaPerLook, ...
                "IntervalMethod","CLOPPER_PEARSON_TWO_SIDED");
        end
    end
end
