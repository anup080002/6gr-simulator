        vectors.Direction(index), vectors.ProfileID(index), ...
        vectors.ChannelModel(index), ...
        vectors.CarrierFrequency_Hz(index), ...
        vectors.Bandwidth_Hz(index), vectors.SCS_kHz(index), ...
        vectors.MCS(index), vectors.Rank(index), ...
