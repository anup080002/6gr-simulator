        "PointKey", sixgr.validation.OperatingPointKey.canonical(point), ...
        "DUTEstimate", actual.DUTEstimate, ...
        "ReferenceEstimate", actual.ReferenceEstimate, ...
        "Difference", actual.Difference, ...
        "DifferenceCILow", actual.DifferenceCILow, ...
        "DifferenceCIHigh", actual.DifferenceCIHigh, ...
        "PointVerdict", actual.EquivalenceVerdict + "|" + ...
