classdef ValidationPhaseEvidenceBuilder
    %VALIDATIONPHASEEVIDENCEBUILDER Build Phase-14 evidence from executions.
    %
    % No table is padded with fallback rows. Every row is produced from a
    % production validator, a fresh canonical runtime, or an independently
    % hashed oracle/reference artifact.

    methods (Static)
        function summary = build(vectorRoot, outputDir, results, ...
                junitPath, canonical, oracleRegistryPath)
            vectorRoot = char(string(vectorRoot));
            outputDir = char(string(outputDir));
            sixgr.util.ensureFolder(outputDir);
            contract = localRead(vectorRoot, ...
                "desired_validation_csv_contract.csv");
            localCleanContractedArtifacts(outputDir, contract, vectorRoot);

            tables = struct();
            tables.validation_profile_resolution = localProfiles(vectorRoot);
            tables.validation_schema_results = localSchemas(vectorRoot);
            [tables.validation_point_status, ...
                tables.validation_sequential_decisions] = ...
                localSequential(vectorRoot, canonical.Scenarios.RunID(1));
            tables.validation_stop_reason_ledger = ...
                localStopReasons(vectorRoot, canonical.Scenarios.RunID(1));
            tables.validation_binomial_intervals = localIntervals(vectorRoot);
            tables.validation_zero_error_bounds = localZeroBounds(vectorRoot);
            tables.validation_multiseed_aggregation = ...
                localMultiseed(vectorRoot);
            tables.validation_operating_point_join = localJoins(vectorRoot);
            tables.validation_curve_comparison = localCurves(vectorRoot);
            oracle = readtable(oracleRegistryPath, ...
                "TextType", "string", "Delimiter", ",");
            tables.validation_reference_registry = ...
                localReferences(oracle);
            tables.validation_oracle_registry = ...
                localOracleRegistry(oracle);
            tables.validation_oracle_results = ...
                localOracleResults(vectorRoot, oracle);
            [tables.validation_provenance_nodes, ...
                tables.validation_provenance_edges, ...
                tables.validation_provenance_checks] = ...
                localProvenance(vectorRoot, canonical.Scenarios.RunID(1));
            tables.validation_runtime_evidence = canonical.RuntimeEvidence;
            tables.validation_measured_sinr = canonical.MeasuredSINR;
            tables.validation_time_windows = ...
                sixgr.validation.TimeWindowContract( ...
                0, 100, 200, 1000, 1100).asTable( ...
                canonical.Scenarios.RunID(1));
            tables.validation_kpi_sample_ledger = ...
                localKPILedger(canonical.Scenarios.RunID(1));
            tables.validation_task_plan = localTaskPlan();
            tables.validation_task_merge = localTaskMerge(vectorRoot);
            tables.validation_seed_ledger = ...
                localSeedLedger(tables.validation_task_plan);
            tables.validation_canonical_scenarios = canonical.Scenarios;
            tables.validation_archive_acceptance = ...
                localArchive(outputDir, canonical);
            tables.validation_matlab_test_execution = ...
                localMATLABLedger(vectorRoot, results, junitPath);
            tables.validation_negative_tests = localNegatives(vectorRoot);
            tables.validation_test_summary = ...
                localTestSummary(tables.validation_matlab_test_execution);

            % Write all execution-backed tables before auditing them.
            preliminary = setdiff(string(fieldnames(tables)), ...
                ["validation_artifact_requirements", ...
                "validation_artifact_audit", ...
                "validation_publication_gates", ...
                "validation_image_semantic_audit"], "stable");
            for field = reshape(preliminary, 1, [])
                localWriteContractTable(outputDir, contract, ...
                    field + ".csv", tables.(char(field)));
            end

            tables.validation_artifact_requirements = ...
                localArtifactRequirements(outputDir, contract);
            localWriteContractTable(outputDir, contract, ...
                "validation_artifact_requirements.csv", ...
                tables.validation_artifact_requirements);
            tables.validation_artifact_audit = ...
                localArtifactAudit(outputDir, contract);
            localWriteContractTable(outputDir, contract, ...
                "validation_artifact_audit.csv", ...
                tables.validation_artifact_audit);
            tables.validation_publication_gates = ...
                localPublicationGates(outputDir);
            localWriteContractTable(outputDir, contract, ...
                "validation_publication_gates.csv", ...
                tables.validation_publication_gates);

            imageAudit = localImages(vectorRoot, outputDir);
            tables.validation_image_semantic_audit = imageAudit;
            localWriteContractTable(outputDir, contract, ...
                "validation_image_semantic_audit.csv", imageAudit);

            [csvCount, csvRows, csvHashes] = ...
                localContractSummary(outputDir, contract);
            summary = struct("Passed", true, ...
                "CSVCount", csvCount, "PNGCount", height(imageAudit), ...
                "CSVRows", csvRows, "CSVHashes", csvHashes, ...
                "CanonicalScenarios", canonical.Scenarios, ...
                "MeasuredSINRRows", height(canonical.MeasuredSINR), ...
                "OracleRows", height(oracle), ...
                "NegativeCasesExecuted", ...
                    height(tables.validation_negative_tests), ...
                "OutputDir", string(outputDir), "Status", "PASS");
        end
    end
end

function output = localProfiles(root)
vectors = localRead(root, "validation_capability_profile_matrix.csv");
actual = strings(height(vectors), 1);
status = repmat("FAIL", height(vectors), 1);
for index = 1:height(vectors)
    resolution = sixgr.validation.ValidationCapabilityProfile. ...
        resolveFeature(vectors.ProfileID(index), ...
        vectors.FindingID(index), vectors.Feature(index));
    actual(index) = resolution.Outcome;
    if actual(index) == vectors.ExpectedOutcome(index)
        status(index) = "PASS";
    end
end
output = table(vectors.ProfileID, vectors.FindingID, vectors.Feature, ...
    vectors.ExpectedOutcome, actual, status, ...
    'VariableNames', ["ProfileID","FindingID","Feature", ...
    "ExpectedOutcome","ActualOutcome","Status"]);
localRequireAllPass(output, "validation_profile_resolution.csv");
end

function output = localSchemas(root)
vectors = localRead(root, "validation_schema_mutation_vectors.csv");
base = sixgr.validation.ValidationSchemaRegistry.sampleCampaignPoint();
schemaID = repmat("campaign_point_v1", height(vectors), 1);
actualStatus = repmat("FAIL", height(vectors), 1);
errorID = repmat("", height(vectors), 1);
missing = repmat("", height(vectors), 1);
wrong = repmat("", height(vectors), 1);
nonfinite = repmat("", height(vectors), 1);
for index = 1:height(vectors)
    mutated = sixgr.validation.SchemaMutationGenerator.apply( ...
        base, vectors.Mutation(index), vectors.Target(index));
    try
        sixgr.validation.CanonicalSchemaValidator. ...
            validateCampaignPoint(mutated);
        matched = vectors.ExpectedStatus(index) == "PASS";
    catch cause
        errorID(index) = string(cause.identifier);
        matched = errorID(index) == vectors.ExpectedError(index);
    end
    if any(contains(upper(vectors.Mutation(index)), ["MISSING","DELETE"]))
        missing(index) = vectors.Target(index);
    elseif any(contains(upper(vectors.Mutation(index)), ...
            ["TYPE","STRING","UNKNOWN_ENUM"]))
        wrong(index) = vectors.Target(index);
    elseif any(contains(upper(vectors.Mutation(index)), ["NAN","INF"]))
        nonfinite(index) = vectors.Target(index);
    end
    if matched
        actualStatus(index) = "PASS";
    end
end
output = table(schemaID, vectors.CaseID, actualStatus, errorID, ...
    missing, wrong, nonfinite, ...
    'VariableNames', ["SchemaID","CaseID","Status","ErrorID", ...
    "MissingColumns","WrongTypes","NonFiniteFields"]);
localRequireAllPass(output, "validation_schema_results.csv");
end

function [points, decisions] = localSequential(root, runID)
vectors = localRead(root, "validation_sequential_stopping_vectors.csv");
n = height(vectors);
pointRows = repmat(struct("RunID","","TaskID","","PointKey","", ...
    "PointStatus","","StopReason","","TrialCount",0,"ErrorCount",0, ...
    "Status",""), n, 1);
decisionRows = repmat(struct("VectorID","","LookIndex",0, ...
    "TrialCount",0,"ErrorCount",0,"PointStatus","", ...
    "StopReason","","CILow",NaN,"CIHigh",NaN, ...
    "AlphaSpent",NaN,"Status",""), n, 1);
for index = 1:n
    profile = struct("MinTrials", vectors.MinTrials(index), ...
        "MinErrors", vectors.MinErrors(index), ...
        "MaxTrials", vectors.MaxTrials(index), ...
        "MaxLooks", vectors.MaxLooks(index), ...
        "LookSchedule", 1:vectors.MaxLooks(index), ...
        "TargetHalfWidth", vectors.TargetHalfWidth(index), ...
        "TargetZeroErrorUpperBound", ...
            vectors.TargetZeroErrorUpper(index), ...
        "NominalConfidenceLevel", ...
            vectors.NominalConfidenceLevel(index));
    design = sixgr.validation.SequentialDesign.fromProfile(profile);
    actual = sixgr.validation.SequentialStoppingPolicy.evaluate( ...
        vectors.ErrorCount(index), vectors.TrialCount(index), ...
        design, vectors.LookIndex(index));
    matched = actual.PointStatus == vectors.ExpectedStatus(index) && ...
        actual.StopReason == vectors.ExpectedStopReason(index);
    status = localStatus(matched);
    pointRows(index) = struct("RunID", string(runID), ...
        "TaskID", "SEQ-" + string(index), ...
        "PointKey", string(vectors.VectorID(index)), ...
        "PointStatus", actual.PointStatus, ...
        "StopReason", actual.StopReason, ...
        "TrialCount", actual.TrialCount, ...
        "ErrorCount", actual.ErrorCount, "Status", status);
    decisionRows(index) = struct( ...
        "VectorID", string(vectors.VectorID(index)), ...
        "LookIndex", actual.LookIndex, ...
        "TrialCount", actual.TrialCount, ...
        "ErrorCount", actual.ErrorCount, ...
        "PointStatus", actual.PointStatus, ...
        "StopReason", actual.StopReason, ...
        "CILow", actual.Lower, "CIHigh", actual.Upper, ...
        "AlphaSpent", actual.AlphaSpent, "Status", status);
end
points = struct2table(pointRows, "AsArray", true);
decisions = struct2table(decisionRows, "AsArray", true);
localRequireAllPass(points, "validation_point_status.csv");
localRequireAllPass(decisions, "validation_sequential_decisions.csv");
end

function output = localStopReasons(root, runID)
vectors = localRead(root, "validation_status_stop_reason_vectors.csv");
n = height(vectors);
rows = repmat(struct("RunID","","TaskID","","LegacyToken","", ...
    "CanonicalPointStatus","","CanonicalStopReason","", ...
    "MigrationAction","","Status",""), n, 1);
for index = 1:n
    pointStatus = vectors.ExpectedPointStatus(index);
    stopReason = vectors.ExpectedStopReason(index);
    action = vectors.ExpectedAction(index);
    actualPoint = "";
    actualReason = "";
    actualAction = action;
    matched = false;
    try
        if action == "MIGRATE"
            migrated = sixgr.validation.StopReason.migrate( ...
                vectors.InputToken(index));
            actualPoint = migrated.PointStatus;
            actualReason = migrated.StopReason;
            actualAction = migrated.Action;
            matched = actualPoint == pointStatus && ...
                actualReason == stopReason;
        elseif action == "REJECT"
            sixgr.validation.StopReason.migrate(vectors.InputToken(index));
        elseif vectors.TokenKind(index) == "POINT_STATUS"
            actualPoint = sixgr.validation.PointStatus.parse( ...
                vectors.InputToken(index));
            actualReason = stopReason;
            matched = actualPoint == pointStatus;
        else
            actualReason = sixgr.validation.StopReason.parse( ...
                vectors.InputToken(index));
            actualPoint = pointStatus;
            matched = actualReason == stopReason;
        end
    catch cause
        matched = action == "REJECT" && ...
            string(cause.identifier) == ...
            "sixgr:validation:LegacyTokenUnmapped";
        actualPoint = pointStatus;
        actualReason = stopReason;
    end
    rows(index) = struct("RunID", string(runID), ...
        "TaskID", "STOP-" + string(index), ...
        "LegacyToken", string(vectors.InputToken(index)), ...
        "CanonicalPointStatus", actualPoint, ...
        "CanonicalStopReason", actualReason, ...
        "MigrationAction", actualAction, ...
        "Status", localStatus(matched));
end
output = struct2table(rows, "AsArray", true);
localRequireAllPass(output, "validation_stop_reason_ledger.csv");
end

function output = localIntervals(root)
vectors = localRead(root, "validation_binomial_interval_test_vectors.csv");
n = height(vectors);
rows = repmat(struct("VectorID","","Method","", ...
    "SuccessCount",0,"TrialCount",0,"ConfidenceLevel",0, ...
    "Estimate",NaN,"CILow",NaN,"CIHigh",NaN, ...
    "MismatchCount",0,"Status",""), n, 1);
for index = 1:n
    actual = sixgr.validation.BinomialIntervalEngine.compute( ...
        vectors.SuccessCount(index), vectors.TrialCount(index), ...
        vectors.ConfidenceLevel(index), vectors.Method(index));
    delta = abs([actual.Estimate - vectors.ExpectedEstimate(index), ...
        actual.Lower - vectors.ExpectedLower(index), ...
        actual.Upper - vectors.ExpectedUpper(index)]);
    mismatch = nnz(delta > 1e-12);
    rows(index) = struct("VectorID", string(vectors.VectorID(index)), ...
        "Method", actual.Method, ...
        "SuccessCount", actual.ErrorCount, ...
        "TrialCount", actual.TrialCount, ...
        "ConfidenceLevel", actual.ConfidenceLevel, ...
        "Estimate", actual.Estimate, "CILow", actual.Lower, ...
        "CIHigh", actual.Upper, "MismatchCount", mismatch, ...
        "Status", localStatus(mismatch == 0));
end
output = struct2table(rows, "AsArray", true);
localRequireAllPass(output, "validation_binomial_intervals.csv");
end

