function [x, y] = localPlotValues(source, minimum)
n = max(height(source), minimum);
x = (1:n).';
numeric = [];
for index = 1:width(source)
    value = source{:, index};
    if isnumeric(value) || islogical(value)
        candidate = double(value(:));
        if any(isfinite(candidate))
            numeric = candidate(isfinite(candidate));
            break;
        end
    end
end
if isempty(numeric)
    numeric = (1:height(source)).';
end
if numel(numeric) < n
    repeats = ceil(n / max(1, numel(numeric)));
    numeric = repmat(numeric, repeats, 1);
end
y = numeric(1:n);
if all(y == y(1))
    y = y + (0:n-1).' * eps(max(1, abs(y(1))));
end
end

