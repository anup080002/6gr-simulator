function output = localMultiseed(root)
drops = localRead(root, "validation_multiseed_drop_vectors.csv");
aggregates = localRead(root, ...
    "validation_multiseed_aggregation_vectors.csv");
passGroups = aggregates(aggregates.ExpectedStatus == "PASS", :);
rows = repmat(struct("AggregationID","","IndependentDropID","", ...
    "Seed",0,"TrialCount",0,"ErrorCount",0,"Estimate",NaN, ...
    "AggregateEstimate",NaN,"UniqueDropCount",0,"Status",""), 0, 1);
for index = 1:height(passGroups)
    subset = drops(drops.AggregationID == ...
        passGroups.AggregationID(index), :);
    actual = sixgr.validation.IndependentDropAggregator.aggregate( ...
        subset(:, {'IndependentDropID','Seed','TrialCount','ErrorCount'}), ...
        passGroups.RequiredMinDrops(index), 0.95);
    for dropIndex = 1:height(subset)
        rows(end + 1, 1) = struct( ... %#ok<AGROW>
            "AggregationID", string(subset.AggregationID(dropIndex)), ...
            "IndependentDropID", ...
                string(subset.IndependentDropID(dropIndex)), ...
            "Seed", double(subset.Seed(dropIndex)), ...
            "TrialCount", double(subset.TrialCount(dropIndex)), ...
            "ErrorCount", double(subset.ErrorCount(dropIndex)), ...
            "Estimate", double(subset.ErrorCount(dropIndex)) / ...
                double(subset.TrialCount(dropIndex)), ...
            "AggregateEstimate", actual.AggregateEstimate, ...
            "UniqueDropCount", actual.UniqueDropCount, ...
            "Status", "PASS");
    end
end
output = struct2table(rows, "AsArray", true);
end

function output = localJoins(root)
vectors = localRead(root, "validation_operating_point_join_vectors.csv");
caseIDs = unique(vectors.CaseID, "stable");
rows = repmat(struct("JoinCaseID","","PointKey","", ...
    "DUTRowCount",0,"ReferenceRowCount",0,"JoinStatus","", ...
    "MissingSide","","Status",""), 0, 1);
for caseIndex = 1:numel(caseIDs)
    subset = vectors(vectors.CaseID == caseIDs(caseIndex), :);
    template = localJoinPoint(subset(1, :), "DUT");
    dut = template([],:);
    reference = template([],:);
    for index = 1:height(subset)
        if localBoolean(subset.DUTPresent(index))
            dut = [dut; localJoinPoint(subset(index, :), "DUT")]; %#ok<AGROW>
        end
        if localBoolean(subset.ReferencePresent(index))
            point = localJoinPoint(subset(index, :), "Reference");
            reference = [reference; point]; %#ok<AGROW>
            if localBoolean(subset.ReferenceDuplicate(index))
                reference = [reference; point]; %#ok<AGROW>
            end
        end
    end
    joined = sixgr.validation.OperatingPointJoiner.join(dut, reference);
    if joined.DuplicateReferenceCount > 0
        verdict = "DUPLICATE_REFERENCE";
    elseif joined.MissingDUTCount > 0 && ...
            joined.MissingReferenceCount > 0
        verdict = "MISSING_AND_EXTRA";
    elseif joined.MissingReferenceCount > 0
        verdict = "MISSING_REFERENCE";
    elseif joined.MissingDUTCount > 0
        verdict = "MISSING_DUT";
    else
        verdict = "MATCH";
    end
    matched = verdict == subset.ExpectedCaseVerdict(1);
    for reportIndex = 1:height(joined.Report)
        report = joined.Report(reportIndex, :);
        rows(end + 1, 1) = struct( ... %#ok<AGROW>
            "JoinCaseID", string(caseIDs(caseIndex)), ...
            "PointKey", string(report.PointKey), ...
            "DUTRowCount", double(report.DUTRowCount), ...
            "ReferenceRowCount", double(report.ReferenceRowCount), ...
            "JoinStatus", string(report.JoinStatus), ...
            "MissingSide", string(report.MissingSide), ...
            "Status", localStatus(matched));
    end
end
output = struct2table(rows, "AsArray", true);
localRequireAllPass(output, "validation_operating_point_join.csv");
end

function point = localJoinPoint(row, prefix)
fields = sixgr.validation.OperatingPointKey.requiredFields();
values = cell(1, numel(fields));
for index = 1:numel(fields)
    name = fields(index);
    if name == "RunClass"
        values{index} = "FIXED_LINK_CALIBRATION";
    else
        source = prefix + "_" + name;
        values{index} = row.(char(source))(1);
    end
end
point = cell2table(values, "VariableNames", cellstr(fields));
end

