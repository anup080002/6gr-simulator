function output = localOracleRegistry(oracle)
validated = sixgr.validation.IndependentOracleRegistry.validate(oracle);
output = table(validated.OracleID, validated.OracleType, ...
    validated.Feature, validated.SourceName, validated.SourceVersion, ...
    validated.ArtifactSHA256, validated.IndependentOfDUT, ...
    validated.QualifiesForMandatoryGate, validated.Status, ...
    validated.ArtifactPath, ...
    'VariableNames', ["OracleID","OracleType","Feature","SourceName", ...
    "SourceVersion","ArtifactSHA256","IndependentOfDUT","Qualifies", ...
    "Status","ArtifactPath"]);
if any(output.Status ~= "PASS")
    error("sixgr:validation:OracleNotQualified", ...
        "A mandatory materialized oracle did not qualify.");
end
for index = 1:height(output)
    if ~isfile(output.ArtifactPath(index)) || ...
            localFileHash(output.ArtifactPath(index)) ~= ...
            output.ArtifactSHA256(index)
        error("sixgr:validation:OracleHashMismatch", ...
            "Oracle %s is missing or has the wrong hash.", ...
            output.OracleID(index));
    end
end
end

function output = localOracleResults(root, oracle)
vectors = localRead(root, "validation_binomial_interval_test_vectors.csv");
oracleRow = oracle(oracle.Feature == "WILSON_INTERVAL" & ...
    oracle.OracleType == "FROZEN_EXTERNAL_VECTOR", :);
if height(oracleRow) ~= 1
    error("sixgr:validation:OracleFailure", ...
        "Exactly one frozen external Wilson oracle is required.");
end
n = height(vectors);
rows = repmat(struct("OracleID","","VectorID","", ...
    "ExpectedSHA256","","ActualSHA256","", ...
    "MismatchCount",0,"Status",""), n, 1);
for index = 1:n
    actual = sixgr.validation.BinomialIntervalEngine.compute( ...
        vectors.SuccessCount(index), vectors.TrialCount(index), ...
        vectors.ConfidenceLevel(index), vectors.Method(index));
    expectedText = sprintf("%.17g|%.17g|%.17g", ...
        vectors.ExpectedEstimate(index), vectors.ExpectedLower(index), ...
        vectors.ExpectedUpper(index));
    actualText = sprintf("%.17g|%.17g|%.17g", ...
        actual.Estimate, actual.Lower, actual.Upper);
    mismatch = double(any(abs([actual.Estimate - ...
        vectors.ExpectedEstimate(index), actual.Lower - ...
        vectors.ExpectedLower(index), actual.Upper - ...
        vectors.ExpectedUpper(index)]) > 1e-12));
    rows(index) = struct("OracleID", string(oracleRow.OracleID), ...
        "VectorID", string(vectors.VectorID(index)), ...
        "ExpectedSHA256", localTextHash(expectedText), ...
        "ActualSHA256", localTextHash(actualText), ...
        "MismatchCount", mismatch, ...
        "Status", localStatus(mismatch == 0));
end
output = struct2table(rows, "AsArray", true);
localRequireAllPass(output, "validation_oracle_results.csv");
end

function [nodes, edges, checks] = localProvenance(root, runID)
vectors = localRead(root, "validation_provenance_dag_vectors.csv");
n = height(vectors);
nodeRows = repmat(struct("RunID","","NodeID","","FieldName","", ...
    "ProvenanceClass","","RootID","","FormulaID","", ...
    "SourceArtifact","","Status",""), n * 3, 1);
edgeRows = repmat(struct("RunID","","ParentNodeID","", ...
    "ChildNodeID","","Relation","","Status",""), n * 3, 1);
checkRows = repmat(struct("CaseID","","ExpectedNode","", ...
    "AppliedNode","","SharedRoot",false,"Allowed",false, ...
    "ErrorID","","Status",""), n, 1);
cursor = 0;
for index = 1:n
    expectedNode = "EXPECTED-" + string(index);
    appliedNode = "APPLIED-" + string(index);
    verdictNode = "VERDICT-" + string(index);
    for node = [expectedNode, appliedNode, verdictNode]
        cursor = cursor + 1;
        if node == expectedNode
            provenance = vectors.ExpectedProvenance(index);
            rootID = vectors.ExpectedRootID(index);
            formula = "independent_expected";
        elseif node == appliedNode
            provenance = vectors.AppliedProvenance(index);
            rootID = vectors.AppliedRootID(index);
            formula = "runtime_applied";
        else
            provenance = "DERIVED_FROM_OBSERVED_RUNTIME_STATE";
            rootID = "verdict-" + string(index);
            formula = "circularity_check";
        end
        nodeRows(cursor) = struct("RunID", string(runID), ...
            "NodeID", node, "FieldName", string(vectors.CaseID(index)), ...
            "ProvenanceClass", string(provenance), ...
            "RootID", string(rootID), "FormulaID", formula, ...
            "SourceArtifact", ...
                "validation_provenance_dag_vectors.csv", ...
            "Status", "PASS");
        edgeRows(cursor) = struct("RunID", string(runID), ...
            "ParentNodeID", node, "ChildNodeID", verdictNode, ...
            "Relation", "evaluated_by", "Status", "PASS");
    end
    actualError = "";
    allowed = false;
    try
        sixgr.validation.EvidenceCircularityChecker.check( ...
            vectors.ExpectedProvenance(index), ...
            vectors.ExpectedRootID(index), ...
            vectors.AppliedProvenance(index), ...
            vectors.AppliedRootID(index));
        allowed = true;
    catch cause
        actualError = string(cause.identifier);
    end
    expectedAllowed = localBoolean(vectors.ExpectedAllowed(index));
    matched = allowed == expectedAllowed && ...
        (expectedAllowed || actualError == vectors.ExpectedError(index));
    checkRows(index) = struct("CaseID", ...
        string(vectors.CaseID(index)), ...
        "ExpectedNode", expectedNode, "AppliedNode", appliedNode, ...
        "SharedRoot", vectors.ExpectedRootID(index) == ...
            vectors.AppliedRootID(index), "Allowed", allowed, ...
        "ErrorID", actualError, "Status", localStatus(matched));
end
nodes = struct2table(nodeRows, "AsArray", true);
edges = struct2table(edgeRows, "AsArray", true);
checks = struct2table(checkRows, "AsArray", true);
localRequireAllPass(checks, "validation_provenance_checks.csv");
end

