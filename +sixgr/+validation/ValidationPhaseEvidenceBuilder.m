    actual = sixgr.validation.CurveComparisonEngine.comparePoint( ...
        vectors.DUTErrors(index), vectors.DUTTrials(index), ...
        vectors.ReferenceErrors(index), vectors.ReferenceTrials(index), ...
        vectors.ConfidenceLevel(index), ...
        vectors.EquivalenceMargin(index)).toStruct();
