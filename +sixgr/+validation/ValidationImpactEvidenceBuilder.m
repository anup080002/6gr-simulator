function output = localRead(root, name)
output = readtable(fullfile(root, name), "TextType", "string", ...
    "Delimiter", ",", "VariableNamingRule", "preserve");
end

function output = localTableHash(input)
ordered = sortrows(input, input.Properties.VariableNames);
output = localTextHash(jsonencode(table2struct(ordered)));
end

function output = localTextHash(text)
output = string(sixgr.util.sha256Hex( ...
    uint8(unicode2native(char(text), "UTF-8"))));
end

function output = localToolboxVersion()
entries = ver("5G Toolbox");
if isempty(entries), output = "unavailable";
else, output = string(entries(1).Version);
end
end

function localRequirePass(input, name)
if isempty(input) || any(input.Status ~= "PASS")
    error("sixgr:validation:PublicationGateIncomplete", ...
        "%s contains failed evidence.", name);
end
end

function output = localStatus(condition)
if condition, output = "PASS"; else, output = "FAIL"; end
end
