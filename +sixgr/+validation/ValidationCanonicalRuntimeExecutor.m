function localRequireLinkOutput(output, workload)
if ~isstruct(output) || ~isfield(output, "Ok") || ...
        ~logical(output.Ok) || ~isfield(output, "TrialTable") || ...
        ~istable(output.TrialTable) || isempty(output.TrialTable)
    error("sixgr:validation:CanonicalScenarioNotExecuted", ...
        "%s did not return successful production trial evidence.", workload);
end
end

function output = localMeasuredRows(trials, runID, taskID, configuredSNR)
candidates = ["MeasuredTrialSINR_dB","MeasuredSINR_dB", ...
    "PostEqSINR_dB","ReceiverHestSINR_dB"];
source = "";
values = [];
for name = candidates
    if ismember(name, string(trials.Properties.VariableNames))
        candidate = double(trials.(char(name)));
        if any(isfinite(candidate))
            values = candidate;
            source = name;
            break;
        end
    end
end
if isempty(values)
    error("sixgr:validation:MeasuredSINRMissing", ...
        "%s did not produce receiver-derived SINR.", taskID);
end
valid = find(isfinite(values));
rows = repmat(localMeasuredRow(), numel(valid), 1);
for index = 1:numel(valid)
    rowIndex = valid(index);
    checked = sixgr.validation.MeasuredSINRGate.validate( ...
        values(rowIndex), "DECODED_RECEIVER_STATE", 1, ...
        "FIXED_LINK_CALIBRATION", configuredSNR);
    rows(index) = struct( ...
        "RunID", string(runID), ...
        "TaskID", string(taskID) + "-" + string(rowIndex), ...
        "PointKey", string(taskID) + "|trial=" + string(rowIndex), ...
        "MeasuredSINR_dB", checked.MeasuredSINR_dB, ...
        "ConfiguredSNR_dB", double(configuredSNR), ...
        "Difference_dB", checked.MeasuredSINR_dB - double(configuredSNR), ...
        "SampleCount", checked.SampleCount, ...
        "ProvenanceClass", checked.ProvenanceClass, ...
        "Status", "PASS", "MeasurementSource", source);
end
output = struct2table(rows, "AsArray", true);
end

function output = localLinkEvidence(result, measured, workload, runFolder)
output = localEvidenceTable( ...
    ["TrialCount";"ReceiverSINRSampleCount";"BLER"; ...
    "Throughput_Mbps";"RuntimeFolder"], ...
    [string(height(result.TrialTable));string(height(measured)); ...
    string(double(result.BLER));string(double(result.Throughput_Mbps)); ...
    string(runFolder)], ...
    ["count";"count";"ratio";"Mbit/s";"path"], ...
    [height(result.TrialTable);height(measured); ...
    height(result.TrialTable);height(result.TrialTable);1], ...
    "OBSERVED_RUNTIME_STATE");
output.Workload = repmat(string(workload), height(output), 1);
end

function output = localEvidenceTable(fields, values, units, counts, provenance)
output = table(string(fields), string(values), string(units), ...
    repmat(string(provenance), numel(fields), 1), double(counts(:)), ...
    repmat("PASS", numel(fields), 1), ...
    'VariableNames', ["FieldName","Value","Unit","ProvenanceClass", ...
    "ObservedSampleCount","Status"]);
end

function output = localRead(root, name)
output = readtable(fullfile(root, name), ...
    "TextType", "string", "Delimiter", ",");
end

function row = localScenarioRow()
row = struct("ScenarioID", "", "Tier", "", "RunID", "", ...
    "RunClass", "", "SourceCommit", "", "ScenarioSHA256", "", ...
    "StartUTC", "", "EndUTC", "", "RuntimeStatus", "", ...
    "ArtifactStatus", "", "Status", "", "SourceTreeSHA256", "", ...
    "ManifestSHA256", "");
end

function row = localMeasuredRow()
row = struct("RunID", "", "TaskID", "", "PointKey", "", ...
    "MeasuredSINR_dB", NaN, "ConfiguredSNR_dB", NaN, ...
