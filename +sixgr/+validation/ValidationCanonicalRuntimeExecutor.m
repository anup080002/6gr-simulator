function output = localSourceCommit()
[status, text] = system("git rev-parse HEAD");
if status ~= 0
    error("sixgr:validation:ArchiveSourceMismatch", ...
        "Unable to resolve the source commit.");
end
output = strtrim(string(text));
end

function output = localSourceTreeHash()
[status, names] = system( ...
    "git ls-files --cached --others --exclude-standard");
if status ~= 0
    error("sixgr:validation:ArchiveSourceMismatch", ...
        "Unable to enumerate release source files.");
end
files = splitlines(strtrim(string(names)));
files = files(strlength(files) > 0);
normalized = replace(files, "\", "/");
generated = startsWith(normalized, "artifacts/") | ...
    startsWith(normalized, "results/") | ...
    contains(normalized, "/__pycache__/") | ...
    contains(normalized, "/.pytest_cache/");
files = files(~generated);
records = strings(numel(files), 1);
for index = 1:numel(files)
    path = fullfile(pwd, files(index));
    if isfile(path)
        records(index) = replace(files(index), "\", "/") + "|" + ...
            localFileHash(path);
    else
        records(index) = replace(files(index), "\", "/") + "|MISSING";
    end
end
payload = join(sort(records), newline);
output = string(sixgr.util.sha256Hex( ...
    uint8(unicode2native(char(payload), "UTF-8"))));
end

function output = localFileHash(path)
fid = fopen(path, "rb");
if fid < 0
    error("sixgr:validation:ArtifactMissing", ...
        "Unable to hash %s.", string(path));
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
output = string(sixgr.util.sha256Hex(fread(fid, Inf, "*uint8")));
end

function output = localUTCNow()
output = string(datetime("now", "TimeZone", "UTC", ...
    "Format", "yyyy-MM-dd'T'HH:mm:ss.SSS'Z'"));
end

function localWriteJSON(path, input)
sixgr.util.jsonWrite(path, input);
end
