classdef ValidationCanonicalRuntimeExecutor
    %VALIDATIONCANONICALRUNTIMEEXECUTOR Execute five fresh Phase-14 workloads.
    %
    % The two fixed-link workloads execute the production DL and UL waveform
    % chains and supply receiver-derived SINR. The remaining workloads execute
    % the production schema, statistics and deterministic-merge engines. Every
    % workload writes a fresh manifest and evidence CSV under its unique RunID.

    methods (Static)
        function result = run(vectorRoot, outputDir)
            vectorRoot = char(string(vectorRoot));
            outputDir = char(string(outputDir));
            runtimeRoot = fullfile(outputDir, "canonical_runtime");
            sixgr.util.ensureFolder(runtimeRoot);
            workloads = ["DL_FIXED_LINK";"UL_FIXED_LINK"; ...
                "SCHEMA_MUTATIONS";"STATISTICAL_INTERVALS"; ...
                "DETERMINISTIC_MERGE"];
            runClasses = ["FIXED_LINK_CALIBRATION"; ...
                "FIXED_LINK_CALIBRATION";"CONTROL_ONLY"; ...
                "CONTROL_ONLY";"CONTROL_ONLY"];
            sourceCommit = localSourceCommit();
            sourceTreeHash = localSourceTreeHash();
            scenarioRows = repmat(localScenarioRow(), numel(workloads), 1);
            measuredRows = repmat(localMeasuredRow(), 0, 1);
            runtimeRows = repmat(localRuntimeRow(), 0, 1);

            for index = 1:numel(workloads)
                workload = workloads(index);
                runID = "VALCAN-" + workload + "-" + ...
                    replace(string(char(java.util.UUID.randomUUID())), "-", "");
                runFolder = fullfile(runtimeRoot, char(runID));
                sixgr.util.ensureFolder(runFolder);
                configPath = fullfile(runFolder, "scenario.json");
                config = struct("SchemaVersion", "1.0.0", ...
                    "ScenarioID", char("validation_" + lower(workload)), ...
                    "Workload", char(workload), ...
                    "RunClass", char(runClasses(index)), ...
                    "Seed", 14014 + index, ...
                    "SourceCommit", char(sourceCommit), ...
                    "SourceTreeSHA256", char(sourceTreeHash));
                localWriteJSON(configPath, config);
                scenarioHash = localFileHash(configPath);
                startUTC = localUTCNow();
                [evidence, measured] = localExecute( ...
                    workload, vectorRoot, runID, runFolder, config.Seed);
                evidencePath = fullfile(runFolder, "runtime_evidence.csv");
                sixgr.util.csvWriteTable(evidencePath, evidence);
                if ~isempty(measured)
                    sixgr.util.csvWriteTable(fullfile(runFolder, ...
                        "measured_sinr.csv"), measured);
                end
                evidenceHash = localFileHash(evidencePath);
                endUTC = localUTCNow();
                manifest = struct( ...
                    "SchemaVersion", "1.0.0", ...
                    "RunID", char(runID), ...
                    "Workload", char(workload), ...
                    "RunClass", char(runClasses(index)), ...
                    "SourceCommit", char(sourceCommit), ...
                    "SourceTreeSHA256", char(sourceTreeHash), ...
                    "ScenarioSHA256", char(scenarioHash), ...
                    "EvidenceSHA256", char(evidenceHash), ...
                    "StartUTC", char(startUTC), ...
                    "EndUTC", char(endUTC), ...
                    "RuntimeStatus", "PASS", ...
                    "ArtifactStatus", "PASS");
                manifestPath = fullfile(runFolder, "manifest.json");
                sixgr.util.jsonWrite(manifestPath, manifest);

                scenarioRows(index) = struct( ...
                    "ScenarioID", "validation_" + lower(workload), ...
                    "Tier", "SMOKE", "RunID", runID, ...
                    "RunClass", runClasses(index), ...
                    "SourceCommit", sourceCommit, ...
                    "ScenarioSHA256", scenarioHash, ...
                    "StartUTC", startUTC, "EndUTC", endUTC, ...
                    "RuntimeStatus", "PASS", ...
                    "ArtifactStatus", "PASS", "Status", "PASS", ...
                    "SourceTreeSHA256", sourceTreeHash, ...
                    "ManifestSHA256", localFileHash(manifestPath));
                if ~isempty(measured)
                    measuredRows = [measuredRows; ...
                        table2struct(measured, "ToScalar", false)]; %#ok<AGROW>
                end
                for evidenceIndex = 1:height(evidence)
                    runtimeRows(end + 1, 1) = struct( ... %#ok<AGROW>
                        "RunID", runID, ...
                        "TaskID", workload + "-" + string(evidenceIndex), ...
                        "FieldName", string(evidence.FieldName(evidenceIndex)), ...
                        "Value", string(evidence.Value(evidenceIndex)), ...
                        "Unit", string(evidence.Unit(evidenceIndex)), ...
                        "ProvenanceClass", ...
                            string(evidence.ProvenanceClass(evidenceIndex)), ...
                        "ObservedSampleCount", ...
                            double(evidence.ObservedSampleCount(evidenceIndex)), ...
                        "Required", true, "Status", "PASS", ...
                        "SourceArtifact", string(evidencePath));
                end
            end

            scenarioTable = struct2table(scenarioRows, "AsArray", true);
            measuredTable = struct2table(measuredRows, "AsArray", true);
            runtimeTable = struct2table(runtimeRows, "AsArray", true);
            if height(measuredTable) < 20
                error("sixgr:validation:MeasuredSINRMissing", ...
                    "Fresh DL/UL runtime produced %d receiver-derived SINR rows; 20 are required.", ...
                    height(measuredTable));
            end
            measuredTable = measuredTable(1:20, :);
            if height(runtimeTable) < 20
                error("sixgr:validation:ObservedEvidenceMissing", ...
                    "Fresh canonical workloads produced fewer than 20 runtime evidence rows.");
            end
            result = struct("Scenarios", scenarioTable, ...
                "MeasuredSINR", measuredTable, ...
                "RuntimeEvidence", runtimeTable, ...
                "SourceCommit", sourceCommit, ...
                "SourceTreeSHA256", sourceTreeHash, ...
                "Passed", true, "Status", "PASS");
            save(fullfile(outputDir, "canonical_runtime_result.mat"), ...
                "result", "-v7");
        end
    end
end

function [evidence, measured] = localExecute( ...
        workload, vectorRoot, runID, runFolder, seed)
measured = table();
switch workload
    case "DL_FIXED_LINK"
        cfg = localLinkConfig(seed);
        output = sixgr.link.runDLPDSCHThroughput(cfg, ...
            "NumFrames", 12, "SNR_dB", 10, ...
            "ExecutionProfile", "phy_calibration");
        localRequireLinkOutput(output, workload);
        measured = localMeasuredRows(output.TrialTable, runID, workload, 10);
        evidence = localLinkEvidence(output, measured, workload, runFolder);
    case "UL_FIXED_LINK"
        cfg = localLinkConfig(seed);
        output = sixgr.link.runULPUSCHThroughput(cfg, ...
            "NumFrames", 12, "SNR_dB", 10);
        localRequireLinkOutput(output, workload);
        measured = localMeasuredRows(output.TrialTable, runID, workload, 10);
        evidence = localLinkEvidence(output, measured, workload, runFolder);
    case "SCHEMA_MUTATIONS"
        vectors = localRead(vectorRoot, "validation_schema_mutation_vectors.csv");
        base = sixgr.validation.ValidationSchemaRegistry.sampleCampaignPoint();
        accepted = 0;
        rejected = 0;
        for index = 1:height(vectors)
            mutated = sixgr.validation.SchemaMutationGenerator.apply( ...
                base, vectors.Mutation(index), vectors.Target(index));
            actual = "";
            try
                sixgr.validation.CanonicalSchemaValidator. ...
                    validateCampaignPoint(mutated);
                accepted = accepted + 1;
            catch cause
                actual = string(cause.identifier);
                rejected = rejected + 1;
            end
            if vectors.ExpectedStatus(index) == "PASS"
                ok = strlength(actual) == 0;
            else
                ok = actual == vectors.ExpectedError(index);
            end
            if ~ok
                error("sixgr:validation:SchemaMutationMismatch", ...
                    "Schema mutation %s did not produce its declared result.", ...
                    vectors.CaseID(index));
            end
        end
        evidence = localEvidenceTable( ...
            ["CasesExecuted";"AcceptedCases";"RejectedCases";"VectorSHA256"], ...
            [string(height(vectors));string(accepted);string(rejected); ...
            localFileHash(fullfile(vectorRoot, ...
            "validation_schema_mutation_vectors.csv"))], ...
            ["count";"count";"count";"sha256"], ...
            [height(vectors);accepted;rejected;1], ...
            "OBSERVED_RUNTIME_STATE");
    case "STATISTICAL_INTERVALS"
        vectors = localRead(vectorRoot, ...
            "validation_binomial_interval_test_vectors.csv");
        maximumDelta = 0;
        for index = 1:height(vectors)
            actual = sixgr.validation.BinomialIntervalEngine.compute( ...
                vectors.SuccessCount(index), vectors.TrialCount(index), ...
                vectors.ConfidenceLevel(index), vectors.Method(index));
            delta = max(abs([actual.Estimate - vectors.ExpectedEstimate(index), ...
                actual.Lower - vectors.ExpectedLower(index), ...
                actual.Upper - vectors.ExpectedUpper(index)]));
            maximumDelta = max(maximumDelta, delta);
        end
        if maximumDelta > 1e-12
            error("sixgr:validation:NumericalFailure", ...
                "Independent interval vectors differ by %.17g.", maximumDelta);
        end
        evidence = localEvidenceTable( ...
            ["VectorsExecuted";"MaximumAbsoluteDelta"; ...
            "ConfidenceLevelCount";"VectorSHA256"], ...
            [string(height(vectors));string(maximumDelta); ...
            string(numel(unique(vectors.ConfidenceLevel))); ...
            localFileHash(fullfile(vectorRoot, ...
            "validation_binomial_interval_test_vectors.csv"))], ...
            ["count";"ratio";"count";"sha256"], ...
            [height(vectors);height(vectors); ...
            numel(unique(vectors.ConfidenceLevel));1], ...
            "OBSERVED_RUNTIME_STATE");
    case "DETERMINISTIC_MERGE"
        vectors = localRead(vectorRoot, ...
            "validation_parallel_merge_vectors.csv");
        expected = localRead(vectorRoot, ...
            "validation_parallel_merge_expected.csv");
        passCount = 0;
        for index = 1:height(expected)
            rows = vectors(vectors.CampaignID == expected.CampaignID(index), ...
                {'TaskID','OutputSHA256','RetryIndex'});
            if expected.ExpectedStatus(index) == "PASS"
                serial = sixgr.validation.DeterministicMergeEngine.merge(rows);
                rng(double(seed) + index, "twister");
                shuffled = sixgr.validation.DeterministicMergeEngine.merge( ...
                    rows(randperm(height(rows)), :));
                if ~isequal(serial.Merged, shuffled.Merged)
                    error("sixgr:validation:ParallelMergeNondeterministic", ...
                        "Campaign %s depends on merge order.", ...
                        expected.CampaignID(index));
                end
                passCount = passCount + 1;
            else
                actual = "";
                try
                    sixgr.validation.DeterministicMergeEngine.merge(rows);
                catch cause
                    actual = string(cause.identifier);
                end
                if actual ~= "sixgr:validation:DuplicateTaskConflict"
                    error("sixgr:validation:DuplicateTaskConflict", ...
                        "Conflict campaign did not fail with the typed error.");
                end
                passCount = passCount + 1;
            end
        end
        evidence = localEvidenceTable( ...
            ["CampaignsExecuted";"CampaignsMatched"; ...
            "MergeRows";"VectorSHA256"], ...
            [string(height(expected));string(passCount); ...
            string(height(vectors));localFileHash(fullfile(vectorRoot, ...
            "validation_parallel_merge_vectors.csv"))], ...
            ["count";"count";"count";"sha256"], ...
            [height(expected);passCount;height(vectors);1], ...
            "OBSERVED_RUNTIME_STATE");
    otherwise
        error("sixgr:validation:CanonicalScenarioNotExecuted", ...
            "Unknown canonical workload %s.", workload);
end
end

