function requested = localCanonicalBlockList(blocks)
if isempty(blocks)
    requested = strings(0, 1);
    return;
end
blocks = string(blocks);
requested = strings(numel(blocks), 1);
for i = 1:numel(blocks)
    requested(i) = localCanonicalBlock(blocks(i));
end
requested = unique(requested(:), "stable");
end

function key = localCanonicalBlock(block)
key = upper(regexprep(string(block), "[^A-Za-z0-9]", ""));
end

function enabled = localBlockEnabled(cfg, d, requested)
if ~isempty(requested)
    enabled = any(requested == string(d.CanonicalBlock));
    return;
end

switch string(d.CanonicalBlock)
    case "DLPDSCH"
        direction = lower(strtrim(string(sixgr.util.structGet(cfg, "simulation.link_direction", ""))));
        enabled = any(direction == ["dl", "downlink", "both"]) || localCfgBool(cfg, ["phy.pdsch.enabled", "pdsch.enabled"], false);
    case "PDCCH"
        enabled = localCfgBool(cfg, ["control.pdcch_enabled", "phy.pdcch.enabled"], false);
    case "PUCCH"
        enabled = localCfgBool(cfg, ["control.pucch_enabled", "phy.pucch.enabled"], false);
    case "PRACH"
        enabled = localCfgBool(cfg, ["random_access.enabled", "phy.prach.enabled"], false);
    case "PBCH"
        enabled = localCfgBool(cfg, ["reference_signals.pbch_enabled", "reference_signals.ssb_enabled", "phy.ssb.enable"], false);
    case "CSIRS"
        enabled = localCfgBool(cfg, ["reference_signals.csirs_enabled", "phy.csirs.enable"], false);
    case "SRS"
        enabled = localCfgBool(cfg, ["reference_signals.srs_enabled", "phy.srs.enable"], false);
    case "TRS"
        enabled = localCfgBool(cfg, ["reference_signals.trs_enabled", "phy.trs.enable"], false);
    case "HARQ"
        enabled = localCfgBool(cfg, ["harq.enabled", "phy.harq.enabled", "pdsch6gr.HARQEnabled"], false);
    case "RA"
        enabled = localCfgBool(cfg, ["random_access_evidence.four_step_ra_required", "random_access.four_step_enabled"], false);
    case "MUMIMO"
        enabled = localCfgBool(cfg, ["mimo.mu_mimo_enabled", "pdsch6gr.EnableMUMIMOStudy"], false);
    case "MULTITRP"
        enabled = localCfgBool(cfg, ["mimo.multi_trp_enabled", "reference_signals.tracking_rs.multi_trp_enabled"], false);
    otherwise
        enabled = false;
end
end

function tf = localCfgBool(cfg, paths, defaultValue)
tf = logical(defaultValue);
for i = 1:numel(paths)
    value = sixgr.util.structGet(cfg, paths(i), []);
    if isempty(value)
        continue;
    end
    if islogical(value) || isnumeric(value)
        tf = logical(value(1));
        return;
    end
    s = lower(strtrim(string(value)));
    if any(s == ["true", "enabled", "on", "yes", "1"])
        tf = true;
        return;
    elseif any(s == ["false", "disabled", "off", "no", "0"])
        tf = false;
        return;
    end
end
end

function status = localRuntimeStatus(d)
if logical(d.SharedPhysicalRuntime)
    status = "shared_runtime";
elseif logical(d.FailClosedWhenMissing)
    status = "fail_closed_contract";
else
    status = "unsupported_gap";
end
end

function tf = localAllSymbolsPresent(symbols)
symbols = string(symbols);
tf = true;
for i = 1:numel(symbols)
    if ~localSymbolPresent(symbols(i))
        tf = false;
        return;
    end
end
end

function tf = localSymbolPresent(symbol)
symbol = string(symbol);
tf = false;
if strlength(symbol) == 0
    return;
end
parts = split(symbol, ".");
if numel(parts) >= 3
    className = strjoin(parts(1:end-1), ".");
    methodName = char(parts(end));
    try
        mc = meta.class.fromName(char(className));
        if ~isempty(mc)
            names = string({mc.MethodList.Name});
            tf = any(names == string(methodName));
            if tf
                return;
            end
        end
    catch
    end
end
tf = strlength(string(which(char(symbol)))) > 0;
end

function tf = localAllTestsPresent(testNames)
testNames = string(testNames);
tf = true;
for i = 1:numel(testNames)
    if ~localTestPresent(testNames(i))
        tf = false;
        return;
    end
end
end

function tf = localTestPresent(testName)
repoRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
testFile = fullfile(repoRoot, "tests", char(testName) + ".m");
tf = exist(testFile, "file") == 2 || strlength(string(which(char(testName)))) > 0;
end
