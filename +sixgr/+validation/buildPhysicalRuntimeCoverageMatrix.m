function T = buildPhysicalRuntimeCoverageMatrix(cfg, varargin)
%BUILDPHYSICALRUNTIMECOVERAGEMATRIX Audit enabled PHY/control runtime wiring.
% The matrix is intentionally contract-level: an enabled block must either
% execute in the coupled/shared physical runtime or fail closed when required
% runtime evidence is absent. Report-only and synthetic paths do not pass.

if nargin < 1 || isempty(cfg)
    cfg = struct();
end

p = inputParser;
p.addParameter("EnabledBlocks", strings(0, 1), @(x) isstring(x) || ischar(x) || iscellstr(x));
p.addParameter("FailOnGap", false, @(x) islogical(x) || (isnumeric(x) && isscalar(x)));
p.parse(varargin{:});
opt = p.Results;

defs = localDefinitions();
requested = localCanonicalBlockList(opt.EnabledBlocks);
known = string({defs.CanonicalBlock}).';
unknown = setdiff(requested, known);
if ~isempty(unknown)
    error("sixgr:validation:UnknownPhysicalRuntimeBlock", ...
        "Unknown physical-runtime block(s): %s.", strjoin(unknown, ", "));
end

rows = repmat(localEmptyRow(), numel(defs), 1);
for i = 1:numel(defs)
    d = defs(i);
    enabled = localBlockEnabled(cfg, d, requested);
    producerPresent = localAllSymbolsPresent(d.PrimaryRuntimeProducer);
    consumerPresent = localAllSymbolsPresent(d.PrimaryRuntimeConsumer);
    testsPresent = localAllTestsPresent(d.RequiredTests);
    evidencePolicy = string(d.ExecutionEvidencePolicy);
    runtimeOk = logical(d.SharedPhysicalRuntime) || logical(d.FailClosedWhenMissing);
    noReportOnly = ~any(evidencePolicy == ["report_only", "synthetic", "fallback", "proxy_only"]);
    rowPass = ~enabled || (runtimeOk && noReportOnly && producerPresent && consumerPresent && testsPresent);

    rows(i).Block = string(d.Block);
    rows(i).CanonicalBlock = string(d.CanonicalBlock);
    rows(i).Family = string(d.Family);
    rows(i).Enabled = logical(enabled);
    rows(i).RuntimeStatus = string(localRuntimeStatus(d));
    rows(i).SharedPhysicalRuntime = logical(d.SharedPhysicalRuntime);
    rows(i).FailClosedWhenMissing = logical(d.FailClosedWhenMissing);
    rows(i).FailClosedErrorId = string(d.FailClosedErrorId);
    rows(i).ExecutionEvidencePolicy = evidencePolicy;
    rows(i).PrimaryRuntimeProducer = string(strjoin(d.PrimaryRuntimeProducer, "|"));
    rows(i).PrimaryRuntimeConsumer = string(strjoin(d.PrimaryRuntimeConsumer, "|"));
    rows(i).RequiredEvidence = string(d.RequiredEvidence);
    rows(i).RequiredTests = string(strjoin(d.RequiredTests, "|"));
    rows(i).ProducerPresent = logical(producerPresent);
    rows(i).ConsumerPresent = logical(consumerPresent);
    rows(i).TestAnchorPresent = logical(testsPresent);
    rows(i).CoveragePass = logical(rowPass);
    rows(i).Notes = string(d.Notes);
end

T = struct2table(rows, "AsArray", true);
if logical(opt.FailOnGap)
    bad = T(logical(T.Enabled) & ~logical(T.CoveragePass), :);
    if ~isempty(bad)
        error("sixgr:validation:PhysicalRuntimeCoverageGap", ...
            "Enabled physical-runtime block(s) failed the shared-runtime/fail-closed audit: %s.", ...
            strjoin(string(bad.Block), ", "));
    end
end
end

