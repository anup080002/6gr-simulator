classdef ValidationCapabilityProfile
    %VALIDATIONCAPABILITYPROFILE YAML-backed validation profile resolver.
    methods (Static)
        function result = plan(profileID)
            profileID = lower(strtrim(string(profileID)));
            catalog = sixgr.validation.ValidationCapabilityProfile.catalog();
            field = matlab.lang.makeValidName(char(profileID));
            if ~isfield(catalog.profiles,field)
                error("sixgr:validation:UnsupportedProfile", ...
                    "Unknown validation profile '%s'.",profileID);
            end
            row = catalog.profiles.(field);
            data = struct( ...
                "SchemaVersion",string(catalog.schema_version), ...
                "ProfileID",profileID, ...
                "Supported",logical(row.supported), ...
                "RunClass",sixgr.validation.RunClass.parse(row.run_class), ...
                "PublicationEligible",logical(row.publication_eligible), ...
                "MeasuredSINRRequired",logical(row.measured_sinr_required), ...
                "MinimumIndependentDrops",double(row.minimum_independent_drops), ...
                "MinTrials",double(row.min_trials), ...
                "MinErrors",double(row.min_errors), ...
                "MaxTrials",double(row.max_trials), ...
                "MaxLooks",double(row.max_looks), ...
                "LookSchedule",reshape(double(row.look_schedule),1,[]), ...
                "TargetHalfWidth",double(row.target_half_width), ...
                "TargetZeroErrorUpperBound",double(row.target_zero_error_upper_bound), ...
                "NominalConfidenceLevel",double(row.nominal_confidence_level), ...
                "IntervalMethod",upper(string(row.interval_method)), ...
                "MultiplicityMethod",upper(string(row.multiplicity_method)), ...
                "MinimumCurveOverlap",double(row.minimum_curve_overlap), ...
                "EquivalenceMargin",double(row.equivalence_margin), ...
                "QualifyingOracleTypes", ...
                    sixgr.validation.OracleType.qualifyingValues());
            result = sixgr.validation.ValidationPlanningResult(data);
        end
        function out = catalog()
            persistent value
            if isempty(value)
                here = fileparts(mfilename("fullpath"));
                root = fileparts(fileparts(here));
                path = fullfile(root,"simulator","configs","validation", ...
                    "validation_profiles.yaml");
                value = sixgr.lls6g.config.readConfigFile(path);
            end
            out = value;
        end
    end
end
