function out=measurePhysicalTXSpatialPower(x)
% R=mean(x_column*x_column^H). NOT centered sample covariance: retain DC,
% idle and CP energy, unequal chain powers and complex coherent cross terms.
% Bounded double accumulator; no IQ retained, sample mutation or RNG use.
assert(isfloat(x)&&ismatrix(x)&&~isempty(x)&&~issparse(x), ...
    'RF:SpatialPowerSamples','Require actual dense sample-by-physical-chain IQ.');
n=size(x,1); ports=size(x,2); r=complex(zeros(ports));
for first=1:4096:n
    z=double(x(first:min(n,first+4095),:));
    assert(all(isfinite(z),'all'),'RF:SpatialPowerSamples','TX IQ must be finite.');
    % MATLAB rows are x^T. conjugating the BLAS Gram matrix gives x*x^H.
    r=r+conj(z'*z);
end
r=r/n;
assert(all(isfinite(r),'all'),'RF:SpatialPowerOverflow','TX second moment overflowed.');
out=struct('Contract',"physical_tx_spatial_power/v1", ...
    'SampleCount',double(n),'PhysicalChainCount',double(ports), ...
    'SecondMoment',r,'TotalMeanSquare',real(trace(r)), ...
    'MatrixSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(r), ...
    'Definition',"mean_x_column_times_x_column_H_no_mean_subtraction", ...
    'Plane',"actual_TX_RF_output_before_antenna_channel", ...
    'Population',"all_samples_including_cp_and_idle", ...
    'Source',"actual_composite_physical_chain_TX_RF_output_samples");
end
