function evidence=validateReceiveBranchObservation(observation,replay,binding)
% Join an original complete pre-RF capture to executed identity branch wiring.
% Actual physical owner supplies binding and segments; this function never
% fabricates an RF type, reconstructs samples or applies a TX logical map.
evidence=struct('Available',false,'Status',"unavailable_no_receive_branch_binding", ...
    'ReferencePlane',"internal_physical_receive_element_before_RX_front_end", ...
    'Layout',struct(),'IntervalReceipts',struct([]), ...
    'HardwareConformanceVerified',false,'AccuracyQualified',false);
if nargin<3||isempty(binding)||(isstruct(binding)&&isscalar(binding)&&isempty(fieldnames(binding)))
    return;
end
id='RF:ReceiveBranchObservation';
assert(isstruct(binding)&&isscalar(binding)&&all(isfield(binding,{'Available','Status','Layout'}))&& ...
    islogical(binding.Available)&&isscalar(binding.Available),id,'Retain the physical owner layout binding.');
if ~binding.Available
    assert(any(string(binding.Status)==["unavailable_no_installed_receive_array", ...
        "validated_geometry_unavailable_explicit_RF_reference"]),id,'Unknown missing-layout disposition.');
    evidence.Status=string(binding.Status); return;
end
layout=binding.Layout;
assert(isstruct(layout)&&isscalar(layout)&&isfield(layout,'LayoutSHA256')&& ...
    string(layout.LayoutSHA256)==sha(rmfield(layout,'LayoutSHA256')),id,'Original installed layout digest changed.');
assert(string(layout.Contract)=="sixgr.rx_branch_layout/v1"&& ...
    string(layout.MapKind)=="identity_physical_element_to_RF_input_columns"&& ...
    ~layout.ExecutionVerified&&~layout.StandardizedReferencePointQualified&& ...
    ~layout.HardwareConformanceVerified,id,'Only the original internal identity layout is supported.');
identity=layout.Identity; n=double(identity.NumReceiveRFChains);
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer')&&isscalar(observation)&& ...
    observation.isComplete()&&observation.NumReceiveAntennas==n&& ...
    identity.NumPhysicalElements==n&&observation.SampleRateHz==identity.SampleRateHz&& ...
    isequal(double(layout.PhysicalElementIndexByRFInput0(:).'),0:n-1),id, ...
    'The original complete capture must retain the installed physical/RF branch dimensions and order.');
assert(isstruct(replay)&&isscalar(replay)&&all(isfield(replay, ...
    {'ReceiverID','RuntimeChannelStartSample','RuntimeChannelEndSample','ReceiveStreamExecutionSegments'}))&& ...
    string(replay.ReceiverID)==string(identity.ReceiverID)&& ...
    replay.RuntimeChannelStartSample==observation.StartSample&& ...
    replay.RuntimeChannelEndSample==observation.EndSampleExclusive,id,'Receiver capture identity mismatch.');
segments=replay.ReceiveStreamExecutionSegments;
assert(iscell(segments)&&~isempty(segments),id,'Original RF intervals are required.');
intervals=zeros(numel(segments),2); receipts=struct([]);
for k=1:numel(segments)
    segment=segments{k}; execution=segment.Execution;
    intervals(k,:)=[segment.StartSample segment.EndSampleExclusive];
    assert(execution.StartSample<=segment.StartSample&& ...
        execution.EndSampleExclusive>=segment.EndSampleExclusive&& ...
        execution.SampleRateHz==identity.SampleRateHz&& ...
        execution.ConfigurationEpoch==identity.PhysicalConfigurationEpoch,id,'Execution clock/layout epoch mismatch.');
    selected=find(string({execution.RX.ID})==string(identity.ReceiverID));
    assert(isscalar(selected),id,'One original endpoint must own every interval.');
    rx=execution.RX(selected).Replay;
    assert(isfield(rx,'ReceiveBranchExecution')&&isstruct(rx.ReceiveBranchExecution)&& ...
        isscalar(rx.ReceiveBranchExecution)&&isfield(rx.ReceiveBranchExecution,'ReceiptSHA256'),id, ...
        'Installed geometry alone is not an executed receiver-branch receipt.');
    receipt=rx.ReceiveBranchExecution;
    assert(string(receipt.ReceiptSHA256)==sha(rmfield(receipt,'ReceiptSHA256'))&& ...
        string(receipt.Contract)=="sixgr.rx_branch_execution/v1"&& ...
        isequaln(receipt.Identity,identity)&&string(receipt.LayoutSHA256)==string(layout.LayoutSHA256)&& ...
        string(receipt.MapKind)==string(layout.MapKind)&& ...
        receipt.ExecutionVerified&&receipt.OriginalSampleOrderingPreserved&& ...
        ~receipt.StandardizedReferencePointQualified&&~receipt.HardwareConformanceVerified,id, ...
        'Use the unchanged actual same-layout identity-wiring receipt.');
    assert(receipt.StartSample==execution.StartSample&&receipt.EndSampleExclusive==execution.EndSampleExclusive&& ...
        receipt.SampleCount==execution.EndSampleExclusive-execution.StartSample&& ...
        receipt.StartSample==rx.RFStreamStartSample&&receipt.EndSampleExclusive==rx.RFStreamEndSampleExclusive&& ...
        identity.PhysicalConfigurationEpoch==rx.RFConfigurationEpoch&& ...
        string(receipt.ElementInputSHA256)==string(receipt.RFInputSHA256)&& ...
        string(receipt.RFInputSHA256)==string(rx.RFInputWaveformSHA256)&& ...
        string(receipt.RFOutputSHA256)==string(rx.RFOutputWaveformSHA256),id, ...
        'The branch receipt must bind the original successful RF call, including intervals clipped by capture boundaries.');
    if isempty(receipts), receipts=receipt; else, receipts(end+1)=receipt; end %#ok<AGROW>
end
assert(intervals(1,1)<=observation.StartSample&&intervals(end,2)>=observation.EndSampleExclusive&& ...
    all(intervals(:,2)>intervals(:,1))&&all(intervals(2:end,1)==intervals(1:end-1,2)),id, ...
    'Executed branch-map intervals must cover the entire original capture without gaps.');
evidence.Available=true;
evidence.Status="verified_modeled_identity_combined_receiver_branch_plane";
evidence.ReferencePlane="modeled_receiver_branch_after_identity_combining_before_RX_front_end";
evidence.Layout=layout; evidence.IntervalReceipts=receipts;
end

function value=sha(value)
value=string(sixgr.util.sha256Hex(unicode2native(jsonencode(value),'UTF-8')));
end
