function installation=validateReceiveBranchInstallation(cfg,receiverID,direction,nPhysical,fs,epoch)
% Validate installed RX geometry without inventing an RF reference type.
% This is the single geometry owner used for both qualified and unavailable
% reference cases. It does not mark any samples or wiring as executed.
id='RF:ReceiveBranchInstallation';
assert(isstruct(cfg)&&isscalar(cfg),id,'Use the installed receiver configuration.');
receiverID=text(receiverID,id); direction=text(direction,id);
assert(any(direction==["DL","UL"]),id,'Declare the actual receiver direction.');
integer(nPhysical,1,id); integer(epoch,0,id);
assert(isnumeric(fs)&&isreal(fs)&&isscalar(fs)&&isfinite(fs)&&fs>0,id,'Invalid sample rate.');
if direction=="UL"
    role="bs"; arrayPath='lls6g.userContext.RuntimeServingBSAntenna';
    metaPath='lls6g.userContext.RuntimeServingBSAntennaMeta';
else
    role="ue"; arrayPath='lls6g.userContext.RuntimeUEAntenna';
    metaPath='lls6g.userContext.RuntimeUEAntennaMeta';
end
a=sixgr.util.structGet(cfg,arrayPath,struct());
m=sixgr.util.structGet(cfg,metaPath,struct());
required=["ArrayObj","NumElements","Fc_Hz","ElementPositions_m", ...
    "ElementOrderingSource","PanelIndexByElement","PolarizationIndexByElement", ...
    "PolarizationAngles_deg","BoresightAzElSlant_deg"];
assert(isstruct(a)&&isscalar(a)&&all(isfield(a,required))&& ...
    isobject(a.ArrayObj)&&isscalar(a.ArrayObj),id,'Retain the actual installed native array.');
n=double(a.NumElements); integer(n,1,id);
nRX=sixgr.util.structGet(cfg,"antenna."+role+".numRxRFChains",NaN); integer(nRX,1,id);
assert(n==nPhysical&&nRX==nPhysical,'RF:ReceiveBranchIdentityUnsupported', ...
    'Identity wiring needs equal actual element, receive RF-chain and input-column counts.');
positions=double(getElementPosition(a.ArrayObj).');
assert(double(getNumElements(a.ArrayObj))==n&&isequal(size(positions),[n 3])&& ...
    all(isfinite(positions(:)))&&isequal(positions,double(a.ElementPositions_m)),id, ...
    'Installed native geometry/order must equal the retained element descriptor.');
fc=sixgr.channel.ChannelFactory.resolveCarrierFrequency(cfg);
assert(isnumeric(a.Fc_Hz)&&isscalar(a.Fc_Hz)&&isfinite(a.Fc_Hz)&& ...
    a.Fc_Hz>0&&double(a.Fc_Hz)==fc,id,'Installed array/carrier frequency mismatch.');
orderSource=text(a.ElementOrderingSource,id);
panel=indexVector(a.PanelIndexByElement,n,id);
polarization=indexVector(a.PolarizationIndexByElement,n,id);
angles=double(a.PolarizationAngles_deg(:).');
assert(~isempty(angles)&&isreal(angles)&&all(isfinite(angles))&& ...
    all(polarization<=numel(angles)),id,'Invalid installed polarization ordering.');
% Position equality alone cannot distinguish co-located polarized elements.
% Retain the actual native element-set order without using handle identity,
% so an equivalent native clone remains a valid physical array definition.
assert(isprop(a.ArrayObj,'ElementSet')&&isprop(a.ArrayObj,'EnablePanelSubarray')&& ...
    ~a.ArrayObj.EnablePanelSubarray,id, ...
    'Identity branches require the installed uncombined native element array.');
elements=a.ArrayObj.ElementSet;
assert(iscell(elements)&&isrow(elements)&&numel(elements)==numel(angles),id, ...
    'Native element-set order must match installed polarization order.');
nativeClasses=strings(1,numel(elements)); nativeAngles=nan(1,numel(elements));
nativePolarized=false(1,numel(elements));
for k=1:numel(elements)
    nativeClasses(k)=string(class(elements{k}));
    nativePolarized(k)=isPolarizationCapable(elements{k});
    if nativePolarized(k)
        assert(isprop(elements{k},'PolarizationAngle'),id, ...
            'Retain an explicit native polarization angle for each polarized element.');
        nativeAngles(k)=double(elements{k}.PolarizationAngle);
        assert(nativeAngles(k)==angles(k),id, ...
            'Actual native polarization order differs from the installed descriptor.');
    end
end
nativeElementOrder=struct('Classes',nativeClasses,'PolarizationCapable',nativePolarized, ...
    'PolarizationAngles_deg',nativeAngles, ...
    'Source',"installed_native_ElementSet_order_not_handle_identity");
boresight=double(a.BoresightAzElSlant_deg(:).');
assert(numel(boresight)==3&&isreal(boresight)&&all(isfinite(boresight)),id, ...
    'Retain the installed element boresight.');
metaFields=["Azimuth_deg","Heading_deg","Tilt_deg","PositionX_m","PositionY_m","PositionZ_m"];
assert(isstruct(m)&&isscalar(m)&&all(isfield(m,metaFields)),id, ...
    'Retain endpoint installation orientation and position metadata.');
orientation=struct();
for name=metaFields
    value=m.(name);
    assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&~isinf(value),id, ...
        'Installation coordinates must be scalar numeric values.');
    orientation.(name)=double(value);
end
assert(all(isfinite([orientation.PositionX_m orientation.PositionY_m ...
    orientation.PositionZ_m orientation.Tilt_deg]))&& ...
    ((role=="bs"&&isfinite(orientation.Azimuth_deg))|| ...
     (role=="ue"&&isfinite(orientation.Heading_deg))),id, ...
    'Actual endpoint position/orientation is required; inactive heading/azimuth may be NaN.');
identity=struct('ReceiverID',receiverID,'Direction',direction,'Role',role, ...
    'NumPhysicalElements',n,'NumReceiveRFChains',double(nRX), ...
    'SampleRateHz',double(fs),'PhysicalConfigurationEpoch',double(epoch));
geometry=struct('NativeArrayClass',string(class(a.ArrayObj)), ...
    'CarrierFrequencyHz',double(fc),'ElementPositions_m',positions, ...
    'ElementOrderingSource',orderSource,'PanelIndexByElement',panel, ...
    'PolarizationIndexByElement',polarization,'PolarizationAngles_deg',angles, ...
    'NativeElementOrder',nativeElementOrder, ...
    'ElementBoresightAzElSlant_deg',boresight,'EndpointInstallation',orientation, ...
    'Coordinates',"native_installed_local_element_order_not_global_rotated_positions");
installation=struct('Identity',identity,'Geometry',geometry);
end

function value=text(value,id)
assert((ischar(value)||isstring(value))&&isscalar(string(value))&& ...
    ~ismissing(string(value))&&strlength(strtrim(string(value)))>0,id,'Explicit scalar text required.');
value=string(value);
end
function integer(value,minimum,id)
assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value)&& ...
    value==fix(value)&&value>=minimum,id,'Exact finite integer required.');
end
function value=indexVector(value,n,id)
assert(isnumeric(value)&&isreal(value)&&isvector(value)&&numel(value)==n&& ...
    all(isfinite(value(:)))&&all(value(:)>=1&value(:)==fix(value(:))),id, ...
    'Retain one exact installed index per physical element.');
value=double(value(:).');
end
