function evidence=validateReceiveElementObservation(observation,replay,binding)
% Original-owner internal element-column observation; not an RF reference.
% Caller supplies its original pre-RF observation handle. No sample read,
% waveform hash, native-array reconstruction or RF execution occurs here.
evidence=struct('Available',false,'Status',"unavailable_original_receive_element_execution", ...
    'ReferencePlane',"internal_physical_receive_element_before_RX_front_end", ...
    'Layout',struct(),'IntervalReceipts',struct([]),'RFReferenceQualified',false, ...
    'PowerUnitQualified',false,'StandardizedReferencePointQualified',false, ...
    'HardwareConformanceVerified',false,'AccuracyQualified',false);
if nargin<3||isempty(binding)||(isstruct(binding)&&isscalar(binding)&&isempty(fieldnames(binding)))
    return;
end
id='RF:ReceiveElementObservation';
assert(isstruct(binding)&&isscalar(binding)&&all(isfield(binding,{'Available','Status','Layout'}))&& ...
    islogical(binding.Available)&&isscalar(binding.Available),id,'Use the original physical-owner element binding.');
if ~binding.Available
    assert(string(binding.Status)=="unavailable_no_original_receive_element_installation",id, ...
        'Unknown missing-installation disposition.');
    evidence.Status=string(binding.Status); return;
end
layout=binding.Layout;
assert(isstruct(layout)&&isscalar(layout)&&isfield(layout,'LayoutSHA256')&& ...
    string(layout.LayoutSHA256)==sha(rmfield(layout,'LayoutSHA256')),id,'Original native layout digest changed.');
assert(string(layout.Contract)=="sixgr.rx_element_layout/v1"&& ...
    string(layout.MapKind)=="identity_installed_element_columns_into_RF_apply"&& ...
    string(layout.ReferencePlane)==evidence.ReferencePlane&& ...
    ~layout.ExecutionVerified&&~layout.RFReferenceQualified&&~layout.PowerUnitQualified&& ...
    ~layout.StandardizedReferencePointQualified&&~layout.HardwareConformanceVerified,id, ...
    'Internal column identity cannot acquire RF, standardized-power or hardware authority.');
identity=layout.Identity; n=identity.NumPhysicalElements;
assert(isa(observation,'sixgr.phy.waveform.WaveformObservationBuffer')&&isscalar(observation)&& ...
    observation.isComplete()&&observation.NumReceiveAntennas==n&&identity.NumReceiveRFChains==n&& ...
    observation.SampleRateHz==identity.SampleRateHz&& ...
    isequal(double(layout.PhysicalElementIndexByInputColumn0(:).'),0:n-1),id, ...
    'The original complete capture must retain the installed element-column dimensions/order.');
assert(isstruct(replay)&&isscalar(replay)&&all(isfield(replay, ...
    {'ReceiverID','RuntimeChannelStartSample','RuntimeChannelEndSample','ReceiveStreamExecutionSegments'}))&& ...
    string(replay.ReceiverID)==string(identity.ReceiverID)&& ...
    replay.RuntimeChannelStartSample==observation.StartSample&& ...
    replay.RuntimeChannelEndSample==observation.EndSampleExclusive,id,'Original receiver/capture identity mismatch.');
segments=replay.ReceiveStreamExecutionSegments;
assert(iscell(segments)&&~isempty(segments),id,'Require original successful RF intervals.');
intervals=zeros(numel(segments),2); receipts=struct([]);
for k=1:numel(segments)
    segment=segments{k}; execution=segment.Execution;
    intervals(k,:)=[segment.StartSample segment.EndSampleExclusive];
    assert(execution.StartSample<=segment.StartSample&&execution.EndSampleExclusive>=segment.EndSampleExclusive&& ...
        execution.SampleRateHz==identity.SampleRateHz&& ...
        execution.ConfigurationEpoch==identity.PhysicalConfigurationEpoch,id,'Execution clock/layout epoch mismatch.');
    selected=find(string({execution.RX.ID})==string(identity.ReceiverID));
    assert(isscalar(selected),id,'One original receiver must own every interval.');
    rx=execution.RX(selected).Replay;
    assert(isfield(rx,'ReceiveElementExecution')&&isstruct(rx.ReceiveElementExecution)&& ...
        isscalar(rx.ReceiveElementExecution)&&isfield(rx.ReceiveElementExecution,'ReceiptSHA256'),id, ...
        'Installed geometry is not a substitute for the original successful element-to-RF execution.');
    receipt=rx.ReceiveElementExecution;
    assert(string(receipt.ReceiptSHA256)==sha(rmfield(receipt,'ReceiptSHA256'))&& ...
        string(receipt.Contract)=="sixgr.rx_element_execution/v1"&& ...
        isequaln(receipt.Identity,identity)&&string(receipt.LayoutSHA256)==string(layout.LayoutSHA256)&& ...
        string(receipt.MapKind)==string(layout.MapKind)&&receipt.ExecutionVerified&& ...
        receipt.OriginalSampleOrderingPreserved&&~receipt.RFReferenceQualified&&~receipt.PowerUnitQualified&& ...
        ~receipt.StandardizedReferencePointQualified&&~receipt.HardwareConformanceVerified&& ...
        string(receipt.HashBindingSource)=="original_RF_producer_hashes_from_restricted_canonical_owner",id, ...
        'Retain the unchanged same-layout original execution receipt without promoting its scope.');
    assert(receipt.StartSample==execution.StartSample&&receipt.EndSampleExclusive==execution.EndSampleExclusive&& ...
        receipt.SampleCount==execution.EndSampleExclusive-execution.StartSample&& ...
        receipt.StartSample==rx.RFStreamStartSample&&receipt.EndSampleExclusive==rx.RFStreamEndSampleExclusive&& ...
        identity.PhysicalConfigurationEpoch==rx.RFConfigurationEpoch&& ...
        string(receipt.ElementInputSHA256)==string(receipt.RFInputSHA256)&& ...
        string(receipt.RFInputSHA256)==string(rx.RFInputWaveformSHA256)&& ...
        string(receipt.RFOutputSHA256)==string(rx.RFOutputWaveformSHA256),id, ...
        'The element receipt must bind the original RF input/output and complete processor interval.');
    if isempty(receipts), receipts=receipt; else, receipts(end+1)=receipt; end %#ok<AGROW>
end
assert(intervals(1,1)<=observation.StartSample&&intervals(end,2)>=observation.EndSampleExclusive&& ...
    all(intervals(:,2)>intervals(:,1))&&all(intervals(2:end,1)==intervals(1:end-1,2)),id, ...
    'Original execution must cover the complete capture without gaps or duplicated intervals.');
evidence.Available=true;
evidence.Status="verified_original_internal_receive_element_columns_not_RF_reference";
evidence.Layout=layout; evidence.IntervalReceipts=receipts;
end

function value=sha(value)
value=string(sixgr.util.sha256Hex(unicode2native(jsonencode(value),'UTF-8')));
end
