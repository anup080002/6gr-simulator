classdef ReceiveElementLayout
    % Original internal receive-element columns, without an RF-type claim.
    % Installation is validated by validateReceiveBranchInstallation. This
    % separate contract neither invents an RF reference nor upgrades the
    % stricter ReceiveBranchLayout. Only the physical owner binds execution.
    methods (Static)
        function binding=freezeInstallation(installation)
            binding=struct('Available',false, ...
                'Status',"unavailable_no_original_receive_element_installation",'Layout',struct());
            if isempty(installation)||(isstruct(installation)&&isscalar(installation)&&isempty(fieldnames(installation)))
                return;
            end
            id='RF:ReceiveElementInstallation';
            assert(isstruct(installation)&&isscalar(installation)&& ...
                all(isfield(installation,{'Identity','Geometry'}))&& ...
                isstruct(installation.Identity)&&isscalar(installation.Identity)&& ...
                isstruct(installation.Geometry)&&isscalar(installation.Geometry),id, ...
                'Retain the original validated native installation, not an inferred antenna count.');
            identity=installation.Identity;
            assert(all(isfield(identity,{'ReceiverID','Direction','Role','NumPhysicalElements', ...
                'NumReceiveRFChains','SampleRateHz','PhysicalConfigurationEpoch'})),id, ...
                'Original endpoint, clock and native dimensions are required.');
            n=identity.NumPhysicalElements;
            assert(isnumeric(n)&&isreal(n)&&isscalar(n)&&isfinite(n)&&n>0&&n==fix(n)&& ...
                isequal(n,identity.NumReceiveRFChains),id,'Identity columns require equal original dimensions.');
            layout=struct('Contract',"sixgr.rx_element_layout/v1", ...
                'Identity',identity,'Geometry',installation.Geometry, ...
                'MapKind',"identity_installed_element_columns_into_RF_apply", ...
                'PhysicalElementIndexByInputColumn0',0:n-1, ...
                'ReferencePlane',"internal_physical_receive_element_before_RX_front_end", ...
                'ExecutionVerified',false,'RFReferenceQualified',false, ...
                'PowerUnitQualified',false,'StandardizedReferencePointQualified',false, ...
                'HardwareConformanceVerified',false);
            layout.LayoutSHA256=sixgr.rf.ReceiveElementLayout.digest(layout);
            binding.Available=true;
            binding.Status="installed_native_element_columns_not_yet_executed";
            binding.Layout=layout;
        end
    end
    methods (Static,Access=?sixgr.truth.SharedWaveformPhysicalRuntime)
        function receipt=bindOriginalOwnerExecution(layout,input,actual,stream,receiverID)
            % The canonical caller passes the SAME preChunk to RF.apply and
            % this method immediately after success. Reuse original hashes;
            % no IQ copy, waveform scan, rehash, or second RF execution.
            id='RF:ReceiveElementExecution';
            assert(isstruct(layout)&&isscalar(layout)&&isfield(layout,'LayoutSHA256')&& ...
                string(layout.LayoutSHA256)==sixgr.rf.ReceiveElementLayout.digest(rmfield(layout,'LayoutSHA256')), ...
                id,'Original element layout digest changed.');
            assert(isa(stream,'sixgr.rf.runtime.RFImpairmentStream')&&isscalar(stream)&& ...
                ~stream.Faulted&&string(stream.Chain.Endpoint)=="rx",id,'Use the original successful RX stream.');
            installation=sixgr.rf.validateReceiveBranchInstallation(stream.Configuration,receiverID, ...
                string(stream.Chain.Direction),stream.NumAntennas,stream.SampleRateHz,stream.ConfigurationEpoch);
            current=sixgr.rf.ReceiveElementLayout.freezeInstallation(installation);
            assert(current.Available&&isequaln(current.Layout,layout),id, ...
                'Original native installation, endpoint, clock or column ordering changed.');
            assert(isa(input,'sixgr.phy.waveform.WaveformChunk')&&isscalar(input),id, ...
                'Use the original immutable RF input chunk.');
            first=input.StartSample; stop=input.EndSample+1;
            assert(isfloat(input.Samples)&&ismatrix(input.Samples)&& ...
                isequal(size(input.Samples),[stop-first stream.NumAntennas])&&stop>first&& ...
                first>=stream.OriginSample&&stream.NextSampleIndex==stop,id, ...
                'Bind the original complete interval immediately after RF application.');
            assert(isstruct(actual)&&isscalar(actual)&& ...
                all(isfield(actual,{'ExecutionStage','Chunk','Config','Replay'}))&& ...
                string(actual.ExecutionStage)=="actual_retained_rf_stream"&& ...
                isequaln(actual.Config,stream.Chain)&& ...
                isa(actual.Chunk,'sixgr.phy.waveform.WaveformChunk')&&isscalar(actual.Chunk)&& ...
                actual.Chunk.StartSample==first&&actual.Chunk.EndSample+1==stop&& ...
                isequal(size(actual.Chunk.Samples),size(input.Samples)),id, ...
                'A prepared, failed, different-owner or different-interval result is not execution.');
            r=actual.Replay;
            required={'RFProcessingMode','RFStreamStartSample','RFStreamEndSampleExclusive', ...
                'RFConfigurationEpoch','RFInputWaveformSHA256','RFOutputWaveformSHA256'};
            assert(isstruct(r)&&isscalar(r)&&all(isfield(r,required))&& ...
                string(r.RFProcessingMode)=="retained_sample_stream"&& ...
                r.RFStreamStartSample==first&&r.RFStreamEndSampleExclusive==stop&& ...
                r.RFConfigurationEpoch==stream.ConfigurationEpoch,id,'Original RF interval identity mismatch.');
            inputHash=string(r.RFInputWaveformSHA256); outputHash=string(r.RFOutputWaveformSHA256);
            for token=[inputHash outputHash]
                assert(isscalar(token)&&~isempty(regexp(char(token),'^[0-9a-fA-F]{64}$','once')),id, ...
                    'Retain the original RF producer input/output hashes.');
            end
            receipt=struct('Contract',"sixgr.rx_element_execution/v1", ...
                'LayoutSHA256',layout.LayoutSHA256,'Identity',layout.Identity, ...
                'StartSample',first,'EndSampleExclusive',stop,'SampleCount',stop-first, ...
                'ElementInputSHA256',inputHash,'RFInputSHA256',inputHash,'RFOutputSHA256',outputHash, ...
                'HashBindingSource',"original_RF_producer_hashes_from_restricted_canonical_owner", ...
                'MapKind',layout.MapKind,'ExecutionVerified',true,'OriginalSampleOrderingPreserved',true, ...
                'RFReferenceQualified',false,'PowerUnitQualified',false, ...
                'StandardizedReferencePointQualified',false,'HardwareConformanceVerified',false, ...
                'Scope',"original_internal_element_input_to_successful_RF_interval_not_power_reference");
            receipt.ReceiptSHA256=sixgr.rf.ReceiveElementLayout.digest(receipt);
        end
    end
    methods (Static,Access=private)
        function value=digest(value)
            value=string(sixgr.util.sha256Hex(unicode2native(jsonencode(value),'UTF-8')));
        end
    end
end
