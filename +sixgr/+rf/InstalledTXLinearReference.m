classdef InstalledTXLinearReference
    % Original-owner binding for an explicitly declared diagnostic TX model.
    % VALUE state: the physical owner commits the returned next model only
    % after its complete RF/channel/RX interval succeeds. Original RF is never
    % replayed. Sample-sized operands and model outputs are transient.
    properties (Access=private)
        Registration struct
        RFStream
        Model = []
        Parents = struct('Receipt',{},'PreparationSHA256',{},'Evidence',{},'TXInstallationSHA256',{},'RegistrationSHA256',{})
        Components = struct('ID',{},'ParentComponentID',{},'ResourceID',{},'ResourceSetID',{}, ...
            'LogicalPortIndex0',{},'ReferencePortNumber',{},'RegistrationSHA256',{}, ...
            'Birth',{},'Samples',{},'Weights',{},'Model',{},'InputNonzeroEndSample',{},'RetireAfterSample',{})
    end
    methods (Static)
        function policy=resolvePolicy(cfg)
            % Missing legacy field means disabled, never retroactive evidence.
            policy=[];
            if ~isfield(cfg,'rf')||~isstruct(cfg.rf)||~isscalar(cfg.rf)||~isfield(cfg.rf,'txLinearReference')
                return;
            end
            policy=cfg.rf.txLinearReference;
            localPolicy(policy);
        end
        function obj=freeze(stream,endpoint,policy)
            id='RF:TXLinearReferenceInstallation';
            localPolicy(policy);
            assert(policy.Enabled&&isa(stream,'sixgr.rf.runtime.RFImpairmentStream')&& ...
                isscalar(stream)&&~stream.Faulted&&string(stream.Chain.Endpoint)=="tx"&& ...
                stream.NextSampleIndex==stream.OriginSample,id, ...
                'Freeze this enabled diagnostic at the original unconsumed TX RF owner.');
            assert(isequaln(policy,sixgr.rf.InstalledTXLinearReference.resolvePolicy(stream.Configuration)), ...
                id,'The model policy must be installed in the original RF configuration.');
            endpoint=localText(endpoint,id);
            power=sixgr.rf.PowerContext(stream.Configuration,stream.Chain.Direction);
            a=struct('ContractVersion',"sixgr.rf.installed_TX_linear_reference/v1", ...
                'EndpointID',endpoint,'Direction',string(stream.Chain.Direction), ...
                'ConfigurationEpoch',stream.ConfigurationEpoch,'SampleRateHz',stream.SampleRateHz, ...
                'NumAntennas',stream.NumAntennas,'OriginSample',stream.OriginSample, ...
                'WaveformAmplitudeUnit',string(power.WaveformAmplitudeUnit),'Policy',policy, ...
                'RFChainSHA256',localDefinitionHash(stream.Chain));
            a.RegistrationSHA256=sixgr.rf.InstalledTXLinearReference.registrationHash(a);
            sixgr.rf.InstalledTXLinearReference.validateRegistration(a);
            obj=sixgr.rf.InstalledTXLinearReference(); obj.Registration=a; obj.RFStream=stream;
        end
        function sha=registrationHash(value)
            % Capsule contains text/scalars only; RF complex arrays have a
            % separate lossless definition hash, not lossy JSON conversion.
            sha=string(sixgr.util.sha256Hex(unicode2native(jsonencode(orderfields(value)),'UTF-8')));
        end
        function validateRegistration(a)
            id='RF:TXLinearReferenceRegistration';
            fields=["ContractVersion","EndpointID","Direction","ConfigurationEpoch", ...
                "SampleRateHz","NumAntennas","OriginSample","WaveformAmplitudeUnit", ...
                "Policy","RFChainSHA256","RegistrationSHA256"];
            assert(isstruct(a)&&isscalar(a)&&isequal(sort(string(fieldnames(a))),sort(fields.')), ...
                id,'Require the exact immutable original TX reference registration.');
            localPolicy(a.Policy);
            assert(a.Policy.Enabled&&localText(a.ContractVersion,id)=="sixgr.rf.installed_TX_linear_reference/v1"&& ...
                any(localText(a.Direction,id)==["DL","UL"])&& ...
                any(localText(a.WaveformAmplitudeUnit,id)==["sqrt_mW","normalized_complex_baseband"]), ...
                id,'Keep the reference model and actual amplitude unit explicit.');
            localText(a.EndpointID,id);
            for name=["ConfigurationEpoch","OriginSample","NumAntennas"]
                v=a.(name); assert(isa(v,'double')&&isreal(v)&&isscalar(v)&& ...
                    isfinite(v)&&v==fix(v)&&v>=0&&v<=flintmax,id,'Invalid original RF coordinate.');
            end
            assert(a.NumAntennas>0&&isa(a.SampleRateHz,'double')&&isreal(a.SampleRateHz)&& ...
                isscalar(a.SampleRateHz)&&isfinite(a.SampleRateHz)&&a.SampleRateHz>0,id,'Invalid RF dimensions.');
            for name=["RFChainSHA256","RegistrationSHA256"]
                assert(~isempty(regexp(char(localText(a.(name),id)),'^[0-9a-f]{64}$','once')), ...
                    id,'Require canonical SHA-256 tokens.');
            end
            assert(string(a.RegistrationSHA256)==sixgr.rf.InstalledTXLinearReference.registrationHash( ...
                rmfield(a,'RegistrationSHA256')),id,'Original registration hash mismatch.');
        end
    end
    methods
        function a=capsule(obj)
            a=obj.Registration;
        end
        function validatePolicy(obj,cfg)
            policy=sixgr.rf.InstalledTXLinearReference.resolvePolicy(cfg);
            assert(~isempty(policy)&&isequaln(policy,obj.Registration.Policy), ...
                'RF:TXLinearReferenceInstallationChanged','The original TX reference policy cannot change midstream.');
        end
        function [next,records,parent]=registerCSIRS(obj,runtime,componentID,prepared)
            % Inputs come from the original accepted queue, not a user-supplied
            % decomposition. Broadcast subscriptions reuse this one producer.
            a=obj.Registration;
            assert(isa(runtime,'sixgr.phy.waveform.WaveformEventRuntime')&& ...
                runtime.NextSampleIndex==obj.RFStream.NextSampleIndex, ...
                'RF:TXReferenceComponentOwner','Register at the original event/RF boundary.');
            q=runtime.originalEnqueueReceipt(a.EndpointID,componentID);
            assert(q.StartSample==prepared.TransmitStartSample&& ...
                q.EndSampleExclusive==q.StartSample+prepared.NumSamples&& ...
                q.SampleRateHz==a.SampleRateHz&&q.NumTransmitAntennas==a.NumAntennas&& ...
                q.NumericClass=="double"&& ...
                string(q.OriginalSampleSHA256)==sixgr.phy.waveform.WaveformHash.numeric(prepared.TransmitSamples), ...
                'RF:TXReferenceComponentOwner','Bind original enqueued samples, columns, precision and support.');
            signature=localPreparationHash(prepared);
            prior=find(arrayfun(@(p)string(p.Receipt.ComponentID)==string(componentID),obj.Parents));
            next=obj;
            if isempty(prior)
                factors=sixgr.phy.refsig.buildCSIRSPortReferenceInputs(prepared);
                assert(string(factors.Evidence.WaveformAmplitudeUnit)==a.WaveformAmplitudeUnit, ...
                    'RF:TXReferenceComponentOwner','Prepared and installed amplitude units differ.');
                parent=struct('Receipt',q,'PreparationSHA256',signature, ...
                    'Evidence',factors.Evidence,'TXInstallationSHA256',a.RegistrationSHA256,'RegistrationSHA256',"");
                parent.RegistrationSHA256=localDefinitionHash(rmfield(parent,'RegistrationSHA256'));
                next.Parents(end+1)=parent;
                for factor=factors.Components
                    if factor.LogicalPortIndex0~=0, continue; end % Actual RSRP target is port 3000.
                    id=string(componentID)+":resource_"+factor.ResourceID+":port_3000";
                    birth=struct('ContractVersion',"sixgr.rf.declared_TX_component_birth/v1", ...
                        'ParentComponentID',string(componentID),'ResourceID',string(factor.ResourceID), ...
                        'LogicalPort',0,'ModelHistoryStartSample',runtime.NextSampleIndex, ...
                        'ComponentSupportStartSample',q.StartSample, ...
                        'ComponentSupportEndSampleExclusive',q.EndSampleExclusive, ...
                        'RegistrationSHA256',parent.RegistrationSHA256);
                    binding=localModelBinding(a,id,"component",q.NumericClass);
                    model=sixgr.rf.runtime.AppliedTXLinearReferenceStream.fromComponentBirth(binding,birth);
                    next.Components(end+1)=struct('ID',id,'ParentComponentID',string(componentID), ...
                        'ResourceID',factor.ResourceID,'ResourceSetID',factor.ResourceSetID, ...
                        'LogicalPortIndex0',0,'ReferencePortNumber',3000, ...
                        'RegistrationSHA256',parent.RegistrationSHA256,'Birth',birth, ...
                        'Samples',factor.Samples,'Weights',factor.WaveformColumnWeights, ...
                        'Model',model,'InputNonzeroEndSample', ...
                        localNonzeroEnd(factor.Samples,q.StartSample),'RetireAfterSample',Inf);
                end
            else
                assert(isscalar(prior)&&isequaln(q,obj.Parents(prior).Receipt)&& ...
                    signature==obj.Parents(prior).PreparationSHA256, ...
                    'RF:TXReferenceBroadcastMismatch','A broadcast cannot acquire different resource/port operands.');
                parent=obj.Parents(prior);
            end
            selected=next.Components(string({next.Components.ParentComponentID})==string(componentID));
            records=rmfield(selected,{'Samples','Weights','Model','RetireAfterSample'});
        end
        function [next,actual,receipt,transient]=apply(obj,stream,endpoint,chunk,epoch)
            % Own the sole original call so no caller-supplied coefficient or
            % oscillator array can acquire an original-execution certificate.
            a=obj.Registration; expected=a.OriginSample;
            if ~isempty(obj.Model), expected=obj.Model.NextSampleIndex; end
            assert(isa(stream,'sixgr.rf.runtime.RFImpairmentStream')&&isscalar(stream)&& ...
                stream==obj.RFStream&&~stream.Faulted&&string(endpoint)==a.EndpointID&& ...
                string(stream.Chain.Direction)==a.Direction&&stream.OriginSample==a.OriginSample&& ...
                stream.ConfigurationEpoch==a.ConfigurationEpoch&&isequal(epoch,a.ConfigurationEpoch)&& ...
                stream.SampleRateHz==a.SampleRateHz&&stream.NumAntennas==a.NumAntennas&& ...
                isa(chunk,'sixgr.phy.waveform.WaveformChunk')&&isscalar(chunk)&& ...
                chunk.StartSample==expected&&stream.NextSampleIndex==expected, ...
                'RF:TXLinearReferenceOriginalOwner', ...
                'Require the original owner and next model/RF clock before executing any samples.');
            [actual,capture]=stream.apply(chunk,epoch);
            [next,receipt,transient]=obj.bindCompleted(stream,endpoint,chunk,actual,capture);
        end
    end
    methods (Access=private)
        function [next,receipt,transient]=bindCompleted(obj,stream,endpoint,chunk,actual,capture)
            a=obj.Registration; id='RF:TXLinearReferenceOriginalOwner';
            assert(isa(stream,'sixgr.rf.runtime.RFImpairmentStream')&&isscalar(stream)&& ...
                stream==obj.RFStream&&~stream.Faulted&&string(endpoint)==a.EndpointID&& ...
                string(stream.Chain.Direction)==a.Direction&&stream.OriginSample==a.OriginSample&& ...
                stream.ConfigurationEpoch==a.ConfigurationEpoch&&stream.SampleRateHz==a.SampleRateHz&& ...
                stream.NumAntennas==a.NumAntennas,id,'Bind the same original registered RF handle and identity.');
            assert(isa(chunk,'sixgr.phy.waveform.WaveformChunk')&&isscalar(chunk)&& ...
                isstruct(capture)&&isscalar(capture)&& ...
                string(capture.ContractVersion)=="sixgr.rf.OriginalTXOperatorCapture/v1"&& ...
                capture.Available&&~capture.ReferenceModelApplied&&~capture.SharedRuntimeOwnerBound&& ...
                ~capture.WaveformAmplitudeUnitBound&&capture.AdditionalRFExecutions==0&& ...
                string(capture.Endpoint)=="tx"&&string(capture.Direction)==a.Direction&& ...
                capture.OriginSample==a.OriginSample&&capture.ConfigurationEpoch==a.ConfigurationEpoch&& ...
                capture.SampleRateHz==a.SampleRateHz&&capture.NumAntennas==a.NumAntennas&& ...
                capture.StartSample==chunk.StartSample&&capture.EndSampleExclusive==chunk.EndSample+1&& ...
                stream.NextSampleIndex==capture.EndSampleExclusive&& ...
                string(capture.OriginalInputChunkSHA256)==string(chunk.SHA256)&& ...
                string(capture.OriginalOutputChunkSHA256)==string(actual.Chunk.SHA256)&& ...
                string(capture.RFInputWaveformSHA256)==string(actual.Replay.RFInputWaveformSHA256)&& ...
                string(capture.RFOutputWaveformSHA256)==string(actual.Replay.RFOutputWaveformSHA256), ...
                id,'Retain the operands from this exact original RF call, not a substituted reference execution.');
            model=obj.Model;
            if isempty(model)
                assert(chunk.StartSample==a.OriginSample,'RF:TXLinearReferenceHistory', ...
                    'Never initialize aggregate model history after the original RF origin.');
                binding=struct('EndpointID',a.EndpointID,'Direction',a.Direction, ...
                    'ReferenceID',a.EndpointID+":fixed_linear_aggregate",'Role',"aggregate", ...
                    'ConfigurationEpoch',a.ConfigurationEpoch,'SampleRateHz',a.SampleRateHz, ...
                    'NumAntennas',a.NumAntennas,'NumericClass',string(class(chunk.Samples)), ...
                    'WaveformAmplitudeUnit',a.WaveformAmplitudeUnit,'OriginSample',a.OriginSample, ...
                    'HistoryInitialization',"declared_zero_model_state");
                model=sixgr.rf.runtime.AppliedTXLinearReferenceStream(binding);
            end
            interval=capture;
            interval.ContractVersion="sixgr.rf.supplied_TX_operator_interval/v1";
            interval.EndpointID=a.EndpointID; interval.WaveformAmplitudeUnit=a.WaveformAmplitudeUnit;
            interval.InstallationSHA256=a.RegistrationSHA256;
            if interval.Stages.DAC.Enabled
                interval.Stages.DAC.Parameters.ReferenceModel="identity_converter_reference";
            end
            [model,reference,adapter]=model.advance(chunk.Samples,chunk.Samples,actual.Waveform,interval);
            next=obj; next.Model=model;
            receipt=struct('ContractVersion',"sixgr.rf.original_owner_TX_linear_reference/v1", ...
                'Source',"original_registered_TX_RF_owner_fixed_linear_diagnostic_model", ...
                'RegistrationSHA256',a.RegistrationSHA256, ...
                'OriginalInputChunkSHA256',string(chunk.SHA256), ...
                'OriginalOutputChunkSHA256',string(actual.Chunk.SHA256), ...
                'OriginalOwnerBindingVerified',true,'ReceiverEstimatorInput',false, ...
                'AdditionalRFExecutions',0,'AdditionalChannelExecutions',0,'Adapter',adapter);
            % Expand one factor at a time. The accessor owns only transient
            % value references to THIS original capture; it is never placed
            % in Replay, a checkpoint, a callback or an execution receipt.
            transient=struct('AggregateSamples',reference,'Component', ...
                @(id)localComponentReference(obj.Components,id,chunk,actual.Waveform,interval), ...
                'Components',struct('ID',{},'RetireAfterSample',{}));
            memory=0; delay=0;
            if interval.Stages.PA.Enabled
                pa=sixgr.rf.runtime.linearPAReferenceCoefficients(interval.Stages.PA.Parameters.Profile);
                memory=numel(pa.LinearTaps)-1;
            end
            if interval.Stages.Timing.Enabled, delay=interval.Stages.Timing.Parameters.DelaySamples; end
            for k=1:numel(obj.Components)
                c=obj.Components(k);
                assert(memory+delay<=flintmax-c.InputNonzeroEndSample, ...
                    'RF:TXReferenceComponentClock','Finite component tail exceeds exact sample coordinates.');
                retire=c.InputNonzeroEndSample+memory+delay;
                if chunk.StartSample<retire
                    [~,componentModel]=localComponentReference(obj.Components,c.ID,chunk,actual.Waveform,interval);
                    next.Components(k).Model=componentModel;
                else
                    next.Components(k).Model=[]; % Finite input support and memory, not a tolerance test.
                end
                if chunk.EndSample+1>=c.InputNonzeroEndSample
                    next.Components(k).Samples=[]; % Original scalar factors no longer needed for future input.
                end
                next.Components(k).RetireAfterSample=retire;
                transient.Components(end+1)=struct('ID',c.ID,'RetireAfterSample',retire);
            end
        end
    end
end

function binding=localModelBinding(a,id,role,precision)
binding=struct('EndpointID',a.EndpointID,'Direction',a.Direction,'ReferenceID',id,'Role',role, ...
    'ConfigurationEpoch',a.ConfigurationEpoch,'SampleRateHz',a.SampleRateHz, ...
    'NumAntennas',a.NumAntennas,'NumericClass',string(precision), ...
    'WaveformAmplitudeUnit',a.WaveformAmplitudeUnit,'OriginSample',a.OriginSample, ...
    'HistoryInitialization',"declared_zero_model_state");
end
function stop=localNonzeroEnd(samples,first)
last=find(samples~=0,1,'last');
if isempty(last), last=0; end % Valid zero-power input; no invented positive reference.
stop=first+last;
end
function [samples,model,receipt]=localComponentReference(components,id,chunk,actual,interval)
k=find(string({components.ID})==string(id));
assert(isscalar(k),'RF:TXReferenceComponentOwner','Unknown original registered component.');
c=components(k); model=c.Model;
samples=zeros(size(chunk.Samples),'like',chunk.Samples);
if isempty(model)
    assert(chunk.StartSample>=c.RetireAfterSample,'RF:TXReferenceComponentHistory','Missing live component history.');
    receipt=struct('RetiredAfterFiniteSupport',true,'RetireAfterSample',c.RetireAfterSample);
    return;
end
b=c.Birth; first=max(chunk.StartSample,b.ComponentSupportStartSample);
stop=min(chunk.EndSample+1,c.InputNonzeroEndSample);
if first<stop
    samples(first-chunk.StartSample+1:stop-chunk.StartSample,:)= ...
        c.Samples(first-b.ComponentSupportStartSample+1:stop-b.ComponentSupportStartSample)*c.Weights.';
end
[model,samples,receipt]=model.advance(samples,chunk.Samples,actual,interval);
end
function sha=localPreparationHash(p)
% Bind all decomposition operands, excluding UE-specific receive policy.
resources=p.Tx.CSIRSInfo.Resources; maps=p.Tx.CSIRSRuntimeEvent.ResourceEvents;
r=struct('ResourceID',{},'ResourceSetID',{},'NumPorts',{},'Indices',{},'Symbols',{},'Matrix',{});
for k=1:numel(resources)
    r(end+1)=struct('ResourceID',resources(k).ResourceID,'ResourceSetID',resources(k).ResourceSetID, ...
        'NumPorts',resources(k).NumPorts,'Indices',resources(k).Indices, ...
        'Symbols',resources(k).Symbols,'Matrix',maps(k).WaveformPrecoderMatrix);
end
sha=localDefinitionHash(struct('Resources',r,'MappedEvent',p.Tx.CSIRSRuntimeEvent, ...
    'CombinedIndices',p.Tx.CSIRSIndices,'CombinedSymbols',p.Tx.CSIRSSymbols, ...
    'ReferenceIdentity',p.ReferenceIdentity,'RuntimeSlot',p.RuntimeSlot, ...
    'Operator',p.Tx.OFDMInfo,'TxInfoOperator',p.TxInfo.OFDM, ...
    'TxInfoMappedEvent',p.TxInfo.CSIRSRuntimeEvent,'TxInfoGrid',p.TxInfo.PortGrid, ...
    'Carrier',localCarrier(p.Carrier),'TxCarrier',localCarrier(p.Tx.Carrier),'Timeline',p.Timeline, ...
    'Deferred',[p.RFExecutionDeferred p.PAExecutionDeferred p.ChannelExecutionDeferred], ...
    'AmplitudeScale',p.PowerContext.AmplitudeScale, ...
    'Unit',p.PowerContext.WaveformAmplitudeUnit,'OriginalGrid',p.Tx.Grid));
end
function c=localCarrier(carrier)
c=struct();
for name=["NCellID","NSizeGrid","NStartGrid","SubcarrierSpacing","CyclicPrefix","NFrame","NSlot"]
    c.(name)=carrier.(name);
end
end

function localPolicy(p)
id='RF:TXLinearReferencePolicy';
assert(isstruct(p)&&isscalar(p)&&isequal(sort(string(fieldnames(p))), ...
    ["Classification";"Enabled";"Model";"RequirementClass"])&& ...
    islogical(p.Enabled)&&isscalar(p.Enabled)&& ...
    localText(p.Model,id)=="fixed_first_order_pa_identity_dac"&& ...
    localText(p.Classification,id)=="optional_research_experiment"&& ...
    localText(p.RequirementClass,id)=="IMPLEMENTATION_POLICY",id, ...
    'Require the explicit fixed-first-order PA/identity-DAC diagnostic model policy.');
end
function value=localText(value,id)
assert((ischar(value)||isstring(value))&&isscalar(string(value))&& ...
    ~ismissing(string(value))&&strlength(strtrim(string(value)))>0,id,'Require scalar nonempty text.');
value=string(value);
end
function sha=localDefinitionHash(value)
% Compact RF installation identity without complex-JSON truncation or handles.
definition=localDefinition(value);
sha=string(sixgr.util.sha256Hex(unicode2native(jsonencode(definition),'UTF-8')));
end
function d=localDefinition(value)
d=struct('Class',string(class(value)),'Size',double(size(value)));
if isnumeric(value)||islogical(value)
    d.Hash=sixgr.phy.waveform.WaveformHash.runtimeArray(value);
elseif ischar(value)||isstring(value)
    d.Text=value;
elseif iscell(value)
    d.Values=cell(size(value));
    for k=1:numel(value), d.Values{k}=localDefinition(value{k}); end
elseif isstruct(value)
    names=sort(string(fieldnames(value))); d.Values=cell(size(value));
    for k=1:numel(value)
        entry=struct();
        for name=reshape(names,1,[]), entry.(name)=localDefinition(value(k).(name)); end
        d.Values{k}=entry;
    end
elseif isa(value,'sixgr.rf.PhaseNoiseModel')&&isscalar(value)
    % Stable public construction descriptor only, not mutable RNG/process
    % state. Exact canonical profile and each executed phase trajectory are
    % bound separately by the original capture/static/interval hashes.
    d.DefinitionScope="phase_noise_public_construction_descriptor_not_process_state";
    names=["Enable","Level_dBcHz","FrequencyOffset_Hz","SampleRate_Hz", ...
        "Seed","PreferCommBackend","UseCommObj","Backend", ...
        "TruthClassification","ApproximationReason"];
    d.Properties=struct();
    for name=names, d.Properties.(name)=localDefinition(value.(name)); end
else
    error('RF:TXLinearReferenceInstallation','Unsupported RF installation value %s.',class(value));
end
end
