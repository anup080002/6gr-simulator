function out=integrateRadiatedSpatialPower(spatial,field,amplitudeUnit)
%INTEGRATERADIATEDSPATIALPOWER Integrate an explicitly retained array field.
% TS 38.104 V18.8.0 3.1: TRP sums all directions and both polarizations.
% TR 38.901 V18.0.0 7.3.2: power pattern is |F_theta|^2+|F_phi|^2.
% Here field.H/V are transmit responses: e_pol=F_pol.'*x_column.
% This computes the configured field MODEL, not hardware/feed efficiency.
% The numerical integral is never rescaled to make trace(R) equal TRP.
arguments
    spatial (1,1) struct
    field (1,1) struct
    amplitudeUnit (1,1) string
end
assert(amplitudeUnit=="sqrt_mW",'RF:RadiationAbsolutePowerRequired', ...
    'Absolute model radiation power requires actual sqrt(mW) sample authority.');
assert(all(isfield(spatial,{'Contract','SecondMoment','MatrixSHA256','PhysicalChainCount', ...
    'SampleCount','TotalMeanSquare','Plane'})) && ...
    string(spatial.Contract)=="physical_tx_spatial_power/v1" && ...
    string(spatial.Plane)=="actual_TX_RF_output_before_antenna_channel", ...
    'RF:RadiationSpatialSource','Use actual same-interval post-TX-RF second moments.');
r=double(spatial.SecondMoment); n=spatial.PhysicalChainCount;
assert(isequal(size(r),[n n]) && all(isfinite(r),'all') && ...
    string(spatial.MatrixSHA256)==sixgr.phy.waveform.WaveformHash.runtimeArray(r) && ...
    spatial.TotalMeanSquare==real(trace(r)), ...
    'RF:RadiationSpatialSource','Spatial matrix hash, dimensions and power must agree.');
tol=128*eps*max(1,n)*max(norm(r,'fro'),realmin);
assert(norm(r-r','fro')<=tol && min(real(eig((r+r')/2)))>=-tol, ...
    'RF:RadiationSpatialSource','A second moment must be Hermitian positive semidefinite.');
assert(all(isfield(field,{'Contract','H','V','SolidAngle_sr','AzimuthElevation_deg', ...
    'FrequencyHz','Source','Scope'})) && ...
    string(field.Contract)=="transmit_array_field_gain/v1" && ...
    string(field.Scope)=="native_gain_pattern_no_feed_or_mutual_coupling_calibration", ...
    'RF:RadiationFieldContract','Require an explicit array field and its gain-calibration scope.');
h=double(field.H); v=double(field.V); weights=double(field.SolidAngle_sr(:));
directions=size(h,2);
assert(isequal(size(h),[n directions]) && isequal(size(v),size(h)) && ...
    directions>=1 && numel(weights)==directions && all(isfinite(h),'all') && ...
    all(isfinite(v),'all') && all(isfinite(weights) & weights>0) && ...
    abs(sum(weights)-4*pi)<=1e-10 && ...
    isequal(size(field.AzimuthElevation_deg),[2 directions]) && ...
    all(isfinite(field.AzimuthElevation_deg),'all') && ...
    isscalar(field.FrequencyHz) && isfinite(field.FrequencyHz) && field.FrequencyHz>0, ...
    'RF:RadiationFieldContract','Retain both polarizations and complete 4pi quadrature.');
ph=real(sum(h.*(r*conj(h)),1));
pv=real(sum(v.*(r*conj(v)),1));
powerTolerance=128*eps*max(1,n)*max(norm(r,'fro'),realmin)* ...
    max(1,max(sum(abs(h).^2+abs(v).^2,1)));
assert(all(ph>=-powerTolerance) && all(pv>=-powerTolerance), ...
    'RF:RadiationNegativePower','A physical second moment cannot produce negative directional power.');
% Clip roundoff only after checking its analytical numerical bound.
ph=max(ph,0); pv=max(pv,0); pattern=ph+pv;
trpH=ph*weights/(4*pi); trpV=pv*weights/(4*pi);
ratio=NaN;
if spatial.TotalMeanSquare>0, ratio=(trpH+trpV)/spatial.TotalMeanSquare; end
[peak,index]=max(pattern);
out=struct('Contract',"modeled_radiated_spatial_power/v1", ...
    'ModelTRP_mW',trpH+trpV,'ModelHorizontalTRP_mW',trpH,'ModelVerticalTRP_mW',trpV, ...
    'ModelDirectionalEIRP_mW',pattern,'ModelHorizontalEIRP_mW',ph,'ModelVerticalEIRP_mW',pv, ...
    'SampledPeakModelEIRP_mW',peak,'SampledPeakAzEl_deg',field.AzimuthElevation_deg(:,index), ...
    'GridPeakIsContinuousPeak',false,'RadiationToInternalPowerRatio',ratio, ...
    'InternalMeanSquare_mW',spatial.TotalMeanSquare,'SampleCount',spatial.SampleCount, ...
    'SpatialMatrixSHA256',string(spatial.MatrixSHA256), ...
    'FieldHSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(h), ...
    'FieldVSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(v), ...
    'DirectionsSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(double(field.AzimuthElevation_deg)), ...
    'WeightsSHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(weights), ...
    'SolidAngle_sr',sum(weights),'FrequencyHz',field.FrequencyHz, ...
    'ReferencePlane',"configured_far_field_pattern_model_from_actual_post_TX_RF_covariance", ...
    'Source',string(field.Source),'Scope',string(field.Scope), ...
    'PowerRenormalizationApplied',false,'HardwareConformanceVerified',false, ...
    'FeedPowerConservationQualified',false);
end
