function out=measureSpatialMappingPower(input,output,matrix)
%MEASURESPATIALMAPPINGPOWER Audit an actually executed linear spatial map.
% Samples are rows: y = x * W.'; uncentered moments obey Ry = W*Rx*W'.
% Retain complex cross terms, unequal powers, CP and idle samples. This is
% internal digital mapping evidence, NOT TRP, EIRP or an RF efficiency test.
% No normalization, sample repair or RNG operation is performed here.
assert(isfloat(input) && isfloat(output) && isfloat(matrix) && ...
    ismatrix(input) && ismatrix(output) && ismatrix(matrix) && ...
    ~isempty(input) && size(input,1)==size(output,1) && ...
    size(matrix,2)==size(input,2) && size(matrix,1)==size(output,2) && ...
    all(isfinite(matrix),'all'), ...
    'RF:SpatialMappingShape','Require aligned actual input/output and output-by-input matrix.');
a=sixgr.rf.measurePhysicalTXSpatialPower(input);
b=sixgr.rf.measurePhysicalTXSpatialPower(output);
w=double(matrix);
expected=w*a.SecondMoment*w';
residual=norm(b.SecondMoment-expected,'fro');
scale=max(norm(expected,'fro'),norm(b.SecondMoment,'fro'));
% Bound accumulated BLAS rounding; this is a numerical identity tolerance,
% not an RF/EVM or 3GPP performance threshold. Float precision is recorded.
precision=eps('double');
if isa(input,'single') || isa(output,'single') || isa(matrix,'single')
    precision=double(eps('single'));
end
tolerance=128*precision*max([1 size(matrix)])*scale;
assert(residual<=tolerance,'RF:SpatialMappingMismatch', ...
    'Actual output covariance disagrees with W*Rx*W^H (residual %.17g, tolerance %.17g).',residual,tolerance);
out=struct('Contract',"executed_spatial_mapping_power/v1", ...
    'SampleCount',size(input,1),'InputColumns',size(input,2),'OutputColumns',size(output,2), ...
    'InputSecondMoment',a.SecondMoment,'OutputSecondMoment',b.SecondMoment, ...
    'ExpectedOutputSecondMoment',expected, ...
    'InputMeanSquare',a.TotalMeanSquare,'OutputMeanSquare',b.TotalMeanSquare, ...
    'ExpectedOutputMeanSquare',real(trace(expected)), ...
    'CovarianceResidual',residual,'NumericalTolerance',tolerance, ...
    'InputArraySHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(input), ...
    'OutputArraySHA256',sixgr.phy.waveform.WaveformHash.runtimeArray(output), ...
    'MatrixSHA256',sixgr.phy.mimo.MatrixContract.digest(w), ...
    'InputPrecision',string(class(input)),'OutputPrecision',string(class(output)), ...
    'MatrixPrecision',string(class(matrix)), ...
    'Population',"same_samples_including_cp_and_idle_no_mean_subtraction", ...
    'ReferencePlane',"digital_spatial_map_before_shared_TX_RF", ...
    'Source',"actual_input_and_mapped_output_samples", ...
    'RadiatedPowerClaimed',false);
end
