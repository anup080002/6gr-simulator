function out=resolveBSRFReference(declaration,nTx,nRx)
% Explicit modeled reference, not a manufactured radiated-power measurement.
% TS 38.104 V18.8.0 4.3.3 defines type 1-O at RIB and >=8 TX/RX units.
required=["rf_type","requirement_boundary","budget_plane","antenna_gain_owner","scope"];
assert(isstruct(declaration)&&isscalar(declaration)&& ...
    all(isfield(declaration,required))&&numel(fieldnames(declaration))==numel(required), ...
    'RF:BSReferenceContract','Declare all BS RF reference fields; unknown fields are rejected.');
expected=["1-O","RIB","internal_pre_rf_total","physical_array_channel", ...
    "modeled_integrated_array_not_hardware_qualification"];
for k=1:numel(required)
    value=string(declaration.(required(k)));
    assert(isscalar(value)&&value==expected(k),'RF:BSReferenceContract', ...
        'Supported modeled BS reference requires %s=%s.',required(k),expected(k));
end
assert(isscalar(nTx)&&isfinite(nTx)&&nTx==fix(nTx)&&nTx>=8 && ...
    isscalar(nRx)&&isfinite(nRx)&&nRx==fix(nRx)&&nRx>=8, ...
    'RF:BSReferenceChains','Type 1-O requires at least eight BS TX and eight BS RX units.');
out=struct('Contract',"modeled_bs_rf_reference/v1",'RFType',"1-O", ...
    'RequirementBoundary',"RIB",'BudgetPlane',"internal_pre_rf_total", ...
    'AntennaGainOwner',"physical_array_channel", ...
    'PhysicalTXChains',double(nTx),'PhysicalRXChains',double(nRx), ...
    'HardwareConformanceVerified',false, ...
    'InternalChainPowerIsTRP',false,'InternalChainPowerIsDirectionalEIRP',false, ...
    'RadiatedPowerQualification',"requires_same_execution_array_pattern_integration", ...
    'Specification',"TS 38.104 V18.8.0 4.3.3 and 9.2", ...
    'Scope',"modeled_integrated_array_not_hardware_qualification");
end
