classdef ReceiveBranchLayout
    %RECEIVEBRANCHLAYOUT Installed layout and executed identity wiring evidence.
    % This is an internal physical-element -> RF-input-column contract, NOT
    % a standardized type-1O/2O measurement reference or hardware certificate.
    % freeze consumes an already installed array; it never builds one from
    % YAML or treats a TX logical-port/beam matrix as an RX combiner.
    % bindExecution must be called by the physical owner immediately after
    % its successful retained RF apply, using that call's original chunks.
    % Neither a configuration capsule nor an equality hash alone proves a
    % whole observation, channel-output ordering, or another owner's run.
    methods (Static)
        function layout=freeze(cfg,receiverID,direction,nPhysical,fs,epoch)
            id='RF:ReceiveBranchInstallation';
            installed=sixgr.rf.validateReceiveBranchInstallation( ...
                cfg,receiverID,direction,nPhysical,fs,epoch);
            identity=installed.Identity; geometry=installed.Geometry;
            n=identity.NumPhysicalElements; nRX=identity.NumReceiveRFChains;
            if identity.Direction=="UL", referencePath='rf.bsPowerReference';
            else, referencePath='rf.uePowerReference'; end
            reference=sixgr.util.structGet(cfg,referencePath,struct());
            refFields=["RFType","RequirementBoundary","Scope"];
            assert(isstruct(reference)&&isscalar(reference)&& ...
                all(isfield(reference,refFields)),id,'An explicit installed RF-type reference is required.');
            rfReference=struct();
            for name=refFields
                rfReference.(name)=sixgr.rf.ReceiveBranchLayout.text(reference.(name),id);
            end
            if isfield(reference,'PhysicalRXChains')
                assert(isequal(double(reference.PhysicalRXChains),double(nRX)),id, ...
                    'RF reference and actual receive-chain counts disagree.');
            end
            layout=struct('Contract',"sixgr.rx_branch_layout/v1",'Identity',identity, ...
                'Geometry',geometry,'RFReference',rfReference, ...
                'MapKind',"identity_physical_element_to_RF_input_columns", ...
                'PhysicalElementIndexByRFInput0',0:n-1, ...
                'SourcePlane',"internal_physical_receive_element_before_RX_front_end", ...
                'TargetPlane',"internal_RF_input_columns_before_RX_front_end", ...
                'ExecutionVerified',false,'StandardizedReferencePointQualified',false, ...
                'HardwareConformanceVerified',false);
            layout.LayoutSHA256=sixgr.rf.ReceiveBranchLayout.digest(layout);
        end

        function receipt=bindExecution(layout,elementChunk,rfInputChunk,actual,stream,receiverID)
            % Public component-boundary validation independently hashes the
            % supplied original samples against the producer's receipt.
            receipt=sixgr.rf.ReceiveBranchLayout.bind( ...
                layout,elementChunk,rfInputChunk,actual,stream,receiverID,true);
        end
    end
    methods (Static,Access=?sixgr.truth.SharedWaveformPhysicalRuntime)
        function receipt=bindOriginalOwnerExecution(layout,elementChunk,rfInputChunk,actual,stream,receiverID)
            % Only the canonical physical owner can join its original call
            % operands immediately after RF.apply. Reuse that producer's
            % hashes instead of serializing wide input/output arrays twice.
            receipt=sixgr.rf.ReceiveBranchLayout.bind( ...
                layout,elementChunk,rfInputChunk,actual,stream,receiverID,false);
        end
    end
    methods (Static,Access=private)
        function receipt=bind(layout,elementChunk,rfInputChunk,actual,stream,receiverID,verifySampleHashes)
            id='RF:ReceiveBranchExecution';
            assert(isstruct(layout)&&isscalar(layout)&&isfield(layout,'LayoutSHA256'),id, ...
                'Retain the original installed layout capsule.');
            payload=rmfield(layout,'LayoutSHA256');
            assert(string(layout.LayoutSHA256)==sixgr.rf.ReceiveBranchLayout.digest(payload), ...
                'RF:ReceiveBranchLayoutDigest','Installed layout changed after freezing.');
            assert(isa(stream,'sixgr.rf.runtime.RFImpairmentStream')&&isscalar(stream)&& ...
                ~stream.Faulted&&string(stream.Chain.Endpoint)=="rx",id, ...
                'Bind a successful retained receiver RF owner, not a prepared or block-only result.');
            current=sixgr.rf.ReceiveBranchLayout.freeze(stream.Configuration,receiverID, ...
                string(stream.Chain.Direction),stream.NumAntennas,stream.SampleRateHz,stream.ConfigurationEpoch);
            assert(isequaln(layout,current),'RF:ReceiveBranchOwnerMismatch', ...
                'The RF owner must retain this exact endpoint, installation, epoch and native clock.');
            assert(isa(elementChunk,'sixgr.phy.waveform.WaveformChunk')&&isscalar(elementChunk)&& ...
                isa(rfInputChunk,'sixgr.phy.waveform.WaveformChunk')&&isscalar(rfInputChunk),id, ...
                'Use the actual element and RF input chunks from the same physical call.');
            x=elementChunk.Samples; first=elementChunk.StartSample; stop=elementChunk.EndSample+1;
            assert(isfloat(x)&&ismatrix(x)&&~isempty(x)&&all(isfinite(x(:)))&& ...
                size(x,2)==stream.NumAntennas&&first>=0&&first==fix(first)&& ...
                stop==first+size(x,1)&&rfInputChunk.StartSample==first&& ...
                rfInputChunk.EndSample+1==stop&&isequaln(x,rfInputChunk.Samples), ...
                'RF:ReceiveBranchIdentityNotExecuted', ...
                'Identity wiring requires the original ordered samples, not equal-sized or reweighted columns.');
            assert(isstruct(actual)&&isscalar(actual)&& ...
                all(isfield(actual,{'ExecutionStage','Waveform','Chunk','Config','Replay'}))&& ...
                string(actual.ExecutionStage)=="actual_retained_rf_stream"&& ...
                isequaln(actual.Config,stream.Chain)&& ...
                isa(actual.Chunk,'sixgr.phy.waveform.WaveformChunk')&&isscalar(actual.Chunk)&& ...
                actual.Chunk.StartSample==first&&actual.Chunk.EndSample+1==stop&& ...
                isequaln(actual.Waveform,actual.Chunk.Samples)&& ...
                isequal(size(actual.Waveform),size(x))&&all(isfinite(actual.Waveform(:)))&& ...
                stream.NextSampleIndex==stop,id, ...
                'Bind immediately after the actual successful same-interval RF call.');
            replay=actual.Replay;
            required={'RFProcessingMode','RFStreamStartSample','RFStreamEndSampleExclusive', ...
                'RFConfigurationEpoch','RFInputWaveformSHA256','RFOutputWaveformSHA256'};
            assert(isstruct(replay)&&isscalar(replay)&&all(isfield(replay,required))&& ...
                string(replay.RFProcessingMode)=="retained_sample_stream"&& ...
                replay.RFStreamStartSample==first&&replay.RFStreamEndSampleExclusive==stop&& ...
                replay.RFConfigurationEpoch==stream.ConfigurationEpoch,id, ...
                'The original RF execution receipt must cover the exact input interval and epoch.');
            inputSHA=string(replay.RFInputWaveformSHA256);
            outputSHA=string(replay.RFOutputWaveformSHA256);
            assert(isscalar(inputSHA)&&isscalar(outputSHA)&& ...
                ~isempty(regexp(char(inputSHA),'^[0-9a-fA-F]{64}$','once'))&& ...
                ~isempty(regexp(char(outputSHA),'^[0-9a-fA-F]{64}$','once')),id, ...
                'The original RF producer must retain both numeric waveform hashes.');
            hashBindingSource="original_RF_producer_hashes_from_restricted_canonical_owner";
            if verifySampleHashes
                assert(inputSHA==string(sixgr.rf.waveformSHA256(complex(real(x),imag(x))))&& ...
                    outputSHA==string(sixgr.rf.waveformSHA256(actual.Waveform)),id, ...
                    'Original RF input/output hashes must match the retained actual samples.');
                hashBindingSource="independently_rehashed_original_RF_input_output";
            end
            receipt=struct('Contract',"sixgr.rx_branch_execution/v1", ...
                'LayoutSHA256',layout.LayoutSHA256,'Identity',layout.Identity, ...
                'StartSample',first,'EndSampleExclusive',stop,'SampleCount',size(x,1), ...
                'ElementInputSHA256',inputSHA,'RFInputSHA256',inputSHA,'RFOutputSHA256',outputSHA, ...
                'HashBindingSource',hashBindingSource, ...
                'MapKind',layout.MapKind,'ExecutionVerified',true, ...
                'OriginalSampleOrderingPreserved',true,'NonzeroElementSampleCount',nnz(x), ...
                'StandardizedReferencePointQualified',false,'HardwareConformanceVerified',false, ...
                'Scope',"successful_internal_RF_interval_not_whole_observation_or_channel_order_qualification");
            receipt.ReceiptSHA256=sixgr.rf.ReceiveBranchLayout.digest(receipt);
        end
        function value=text(value,id)
            assert((ischar(value)||isstring(value))&&isscalar(string(value))&& ...
                ~ismissing(string(value))&&strlength(strtrim(string(value)))>0,id,'Explicit scalar text required.');
            value=string(value);
        end
        function sha=digest(value)
            sha=string(sixgr.util.sha256Hex(unicode2native(jsonencode(value),'UTF-8')));
        end
    end
end
