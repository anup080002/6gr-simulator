function field=sampleArrayRadiationField(array,azimuthCount,elevationCount)
%SAMPLEARRAYRADIATIONFIELD Freeze the installed polarimetric array response.
% Quadrature is uniform in azimuth and sin(elevation), so its weights sum
% to 4pi exactly (up to rounding), including neither duplicate azimuth seam
% nor an incorrectly equal-weighted latitude grid. Counts are caller policy.
arguments
    array (1,1) struct
    azimuthCount (1,1) double {mustBeInteger,mustBePositive}
    elevationCount (1,1) double {mustBeInteger,mustBePositive}
end
assert(all(isfield(array,{'ArrayObj','NumElements','Fc_Hz'})) && ...
    ~isempty(array.ArrayObj) && isfinite(array.Fc_Hz) && array.Fc_Hz>0, ...
    'RF:RadiationArrayRequired','Use the actual installed array, not a count-only surrogate.');
az=-180+((0:azimuthCount-1)+0.5)*360/azimuthCount;
el=asind(-1+((0:elevationCount-1)+0.5)*2/elevationCount);
[az,el]=ndgrid(az,el); angles=[az(:).';el(:).'];
response=phased.SteeringVector('SensorArray',clone(array.ArrayObj), ...
    'IncludeElementResponse',true,'EnablePolarization',true);
f=response(array.Fc_Hz,angles);
assert(isstruct(f) && all(isfield(f,{'H','V'})) && ...
    isequal(size(f.H),[array.NumElements numel(az)]) && isequal(size(f.H),size(f.V)), ...
    'RF:RadiationArrayRequired','Require explicit installed-array polarized field components.');
field=struct('Contract',"transmit_array_field_gain/v1",'H',double(f.H),'V',double(f.V), ...
    'SolidAngle_sr',repmat(4*pi/numel(az),numel(az),1), ...
    'AzimuthElevation_deg',angles,'FrequencyHz',double(array.Fc_Hz), ...
    'Source',"installed_array_phased_SteeringVector_with_element_response_and_polarization", ...
    'Scope',"native_gain_pattern_no_feed_or_mutual_coupling_calibration", ...
    'CoordinateFrame',"installed_array_local_coordinates", ...
    'Quadrature',"midpoint_uniform_azimuth_and_sine_elevation", ...
    'AzimuthCount',azimuthCount,'ElevationCount',elevationCount);
end
