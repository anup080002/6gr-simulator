function policy=resolveModeledRadiationPolicy(declaration)
% Explicit opt-in numerical field model; not an RF-type or feed calibration.
id='RF:ModeledRadiationPolicy';
assert(isstruct(declaration)&&isscalar(declaration)&&isfield(declaration,'enabled'),id, ...
    'Declare power_and_rf_frontend.modeled_radiated_power.enabled explicitly.');
enabled=declaration.enabled;
assert((islogical(enabled)||isnumeric(enabled))&&isscalar(enabled)&& ...
    isreal(enabled)&&isfinite(enabled)&&any(enabled==[0 1]),id,'enabled must be boolean.');
policy=struct('Enabled',logical(enabled));
allowed=["enabled","azimuth_count","elevation_count","scope","coordinate_frame","frequency_scope","ue_reference"];
assert(all(ismember(string(fieldnames(declaration)),allowed)),id,'Unknown modeled-radiation policy field.');
if ~enabled, return; end
assert(all(isfield(declaration,allowed)),id,'Enabled radiation requires explicit quadrature, scope and UE model reference.');
for name=["azimuth_count","elevation_count"]
    value=declaration.(name);
    assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value)&&value>=1&&value==fix(value),id, ...
        '%s must be a positive integer; quadrature is caller policy, not an accuracy qualification.',name);
end
assert(exactText(declaration.scope,"native_gain_pattern_post_tx_rf_model")&& ...
    exactText(declaration.coordinate_frame,"installed_array_local_coordinates")&& ...
    exactText(declaration.frequency_scope,"frequency_flat_installed_carrier_field_model"),id, ...
    'Supported scope is the installed local, frequency-flat native field model only.');
u=declaration.ue_reference;
assert(isstruct(u)&&isscalar(u)&& ...
    isequal(sort(string(fieldnames(u))),sort(["rf_type";"requirement_boundary";"scope"]))&& ...
    exactText(u.rf_type,"undeclared_UE_RF_type_model_only")&& ...
    exactText(u.requirement_boundary,"internal_post_TX_RF_model_only")&& ...
    exactText(u.scope,"modeled_integrated_array_not_hardware_qualification"),id, ...
    'Declare the model-only UE boundary; never infer a UE standardized RF type from the BS.');
policy.Quadrature=struct('AzimuthCount',double(declaration.azimuth_count), ...
    'ElevationCount',double(declaration.elevation_count));
policy.Scope=string(declaration.scope);
policy.CoordinateFrame=string(declaration.coordinate_frame);
policy.FrequencyScope=string(declaration.frequency_scope);
policy.UEReference=struct('RFType',string(u.rf_type), ...
    'RequirementBoundary',string(u.requirement_boundary),'Scope',string(u.scope));
end
function yes=exactText(value,expected)
yes=(ischar(value)||isstring(value))&&isscalar(string(value))&& ...
    ~ismissing(string(value))&&string(value)==expected;
end
