classdef InstalledTXRadiationBinding
    % Immutable installed-array/model binding, not an accepted-feed calibration.
    % Freeze the ORIGINAL installed array and RF owner at node registration.
    % No array is reconstructed from YAML and no logical-port matrix is used.
    % The field is sampled once in installed LOCAL coordinates. The model is
    % frequency-flat at the installed carrier, not a wideband radiation solve.
    % The physical owner binds registration, current native channel installation
    % and the original RF interval. Component receipts retain their own scope;
    % the committed owner ledger supplies the separate integration evidence.
    properties (Access=private)
        Installation struct
        Field struct
        RFStream
    end
    methods (Static)
        function validateArchivedField(installation,field)
            id='RF:TXRadiationArchive';
            assert(isstruct(installation)&&isscalar(installation)&& ...
                string(installation.Contract)=="sixgr.installed_TX_radiation/v1"&& ...
                installation.InstallationSHA256==sixgr.rf.InstalledTXRadiationBinding.digest( ...
                rmfield(installation,'InstallationSHA256'))&& ...
                isequaln(installation.FieldIdentity,sixgr.rf.InstalledTXRadiationBinding.fieldIdentity(field)), ...
                id,'Original installation and frozen field hashes must close exactly.');
            assert(~installation.ExecutionVerified&&~installation.AcceptedFeedPowerQualified&& ...
                ~installation.HardwareConformanceVerified&&~installation.PowerRenormalizationApplied&& ...
                installation.CoordinateFrame=="installed_array_local_coordinates"&& ...
                installation.FrequencyScope=="frequency_flat_installed_carrier_field_model",id, ...
                'An immutable field is not executed radiation or hardware qualification.');
        end
        function obj=freeze(array,metadata,stream,transmitterID,policy,rfReference)
            id='RF:TXRadiationInstallation';
            assert(isa(stream,'sixgr.rf.runtime.RFImpairmentStream')&&isscalar(stream)&& ...
                ~stream.Faulted&&string(stream.Chain.Endpoint)=="tx"&& ...
                stream.NextSampleIndex==stream.OriginSample,id, ...
                'Freeze the original, not-yet-consumed TX RF owner at installation.');
            endpoint=sixgr.rf.InstalledTXRadiationBinding.text(transmitterID,id);
            assert(isstruct(policy)&&isscalar(policy)&& ...
                isequal(sort(string(fieldnames(policy))),["AzimuthCount";"ElevationCount"]),id, ...
                'Declare both quadrature counts explicitly; no hidden sampling policy.');
            for name=["AzimuthCount","ElevationCount"]
                sixgr.rf.InstalledTXRadiationBinding.integer(policy.(name),1,id);
            end
            direction=string(stream.Chain.Direction);
            assert(any(direction==["DL","UL"]),id,'Require the actual TX direction.');
            role="bs"; if direction=="UL", role="ue"; end
            geometry=sixgr.rf.InstalledTXRadiationBinding.geometry(array,metadata,role);
            assert(geometry.NumPhysicalElements==stream.NumAntennas,id, ...
                'Original RF output columns must equal original installed physical elements.');
            frequency=sixgr.channel.ChannelFactory.resolveCarrierFrequency(stream.Configuration);
            assert(frequency==geometry.CarrierFrequencyHz,id, ...
                'The original RF owner and installed array must use the same carrier.');
            refFields=["RFType","RequirementBoundary","Scope"];
            assert(isstruct(rfReference)&&isscalar(rfReference)&&all(isfield(rfReference,refFields)),id, ...
                'Retain explicit declared RF-reference metadata; it is not feed calibration.');
            reference=struct();
            for name=refFields
                reference.(name)=sixgr.rf.InstalledTXRadiationBinding.text(rfReference.(name),id);
            end
            power=sixgr.rf.PowerContext(stream.Configuration,direction);
            assert(string(power.WaveformAmplitudeUnit)=="sqrt_mW", ...
                'RF:RadiationAbsolutePowerRequired', ...
                'Normalized samples cannot become absolute modeled power by relabeling.');
            field=sixgr.rf.sampleArrayRadiationField(array, ...
                double(policy.AzimuthCount),double(policy.ElevationCount));
            fieldIdentity=sixgr.rf.InstalledTXRadiationBinding.fieldIdentity(field);
            installation=struct('Contract',"sixgr.installed_TX_radiation/v1", ...
                'TransmitterID',endpoint,'Direction',direction,'Role',role, ...
                'SampleRateHz',stream.SampleRateHz,'PhysicalConfigurationEpoch',stream.ConfigurationEpoch, ...
                'RFStreamOriginSample',stream.OriginSample,'PhysicalChainCount',stream.NumAntennas, ...
                'Geometry',geometry,'DeclaredRFReference',reference, ...
                'WaveformAmplitudeUnit',"sqrt_mW",'FieldIdentity',fieldIdentity, ...
                'CoordinateFrame',"installed_array_local_coordinates", ...
                'FrequencyScope',"frequency_flat_installed_carrier_field_model", ...
                'Source',"original_installed_native_TX_array_and_original_RF_owner", ...
                'ExecutionVerified',false,'AcceptedFeedPowerQualified',false, ...
                'HardwareConformanceVerified',false,'PowerRenormalizationApplied',false);
            installation.InstallationSHA256=sixgr.rf.InstalledTXRadiationBinding.digest(installation);
            obj=sixgr.rf.InstalledTXRadiationBinding();
            obj.Installation=installation; obj.Field=field; obj.RFStream=stream;
        end
    end
    methods
        function validateInstallation(obj,array,metadata,policy,rfReference)
            % Repeated radio registration must not resample the immutable field.
            id='RF:TXRadiationInstallationChanged'; a=obj.Installation;
            g=sixgr.rf.InstalledTXRadiationBinding.geometry(array,metadata,a.Role);
            names=["RFType","RequirementBoundary","Scope"]; reference=struct();
            assert(isstruct(rfReference)&&isscalar(rfReference)&&all(isfield(rfReference,names)),id, ...
                'Require the original explicit RF-reference declaration.');
            for name=names
                reference.(name)=sixgr.rf.InstalledTXRadiationBinding.text(rfReference.(name),id);
            end
            assert(isequaln(g,a.Geometry)&&isequaln(reference,a.DeclaredRFReference)&& ...
                isequal(policy,struct('AzimuthCount',a.FieldIdentity.AzimuthCount, ...
                'ElevationCount',a.FieldIdentity.ElevationCount)),id, ...
                'A shared transmitter cannot change array, orientation, field policy or reference.');
        end
        function value=capsule(obj)
            % Value copy: no mutable array or stream handle escapes.
            value=obj.Installation;
        end
        function value=fieldEvidence(obj)
            % Retain once per installation/archive, not once per RF interval.
            value=obj.Field;
        end
        function receipt=validateChannel(obj,state,transmitterID)
            % Validate actual CURRENT native TX getter. R2026a swaps the
            % property values itself; TransmitAndReceiveSwapped is NOT a
            % reason to read ReceiveAntennaArray a second time.
            id='RF:TXRadiationChannelInstallation';
            obj.checkEndpoint(transmitterID);
            a=obj.Installation;
            required={'Materialized','Obj','NumTxAnt','SampleRate_Hz', ...
                'CurrentSampleIndex','Direction','StateKey'};
            assert(isstruct(state)&&isscalar(state)&&all(isfield(state,required))&& ...
                isequal(state.Materialized,true)&&isa(state.Obj,'nrCDLChannel')&& ...
                state.NumTxAnt==a.PhysicalChainCount&&state.SampleRate_Hz==a.SampleRateHz&& ...
                state.CurrentSampleIndex==obj.RFStream.NextSampleIndex&& ...
                string(state.Direction)==a.Direction&& ...
                isscalar(string(state.StateKey))&&strlength(string(state.StateKey))>0&& ...
                double(state.Obj.CarrierFrequency)==a.Geometry.CarrierFrequencyHz&& ...
                isequal(double(state.Obj.TransmitArrayOrientation(:)),a.Geometry.NativeArrayOrientation_deg),id, ...
                'Require the original materialized native link at the retained owner clock.');
            native=state.Obj.TransmitAntennaArray;
            definition=sixgr.rf.InstalledTXRadiationBinding.nativeDefinition(native,0);
            assert(double(getNumElements(native))==a.PhysicalChainCount&& ...
                isequal(double(getElementPosition(native).'),a.Geometry.ElementPositions_m)&& ...
                isequaln(definition,a.Geometry.NativeDefinition),id, ...
                'Current native transmit geometry, element response, orientation and order must match installation.');
            receipt=struct('Contract',"sixgr.native_TX_radiation_installation/v1", ...
                'InstallationSHA256',a.InstallationSHA256,'TransmitterID',a.TransmitterID, ...
                'Direction',a.Direction,'StateKey',string(state.StateKey), ...
                'AtSample',double(state.CurrentSampleIndex),'SampleRateHz',a.SampleRateHz, ...
                'PhysicalConfigurationEpoch',a.PhysicalConfigurationEpoch, ...
                'NativeGetter',"current_TransmitAntennaArray_no_second_swap", ...
                'NativeDefinitionSHA256',a.Geometry.NativeDefinitionSHA256, ...
                'CarrierFrequencyHz',a.Geometry.CarrierFrequencyHz, ...
                'NativeArrayOrientation_deg',a.Geometry.NativeArrayOrientation_deg, ...
                'Source',"actual_materialized_native_channel_installation", ...
                'WaveformExecutionVerified',false,'HardwareConformanceVerified',false);
            receipt.ReceiptSHA256=sixgr.rf.InstalledTXRadiationBinding.digest(receipt);
        end
        function [receipt,modeled]=bindExecution(obj,input,actual,stream,transmitterID)
            % Strict COMPONENT route: independently recheck original samples
            % and covariance. No public trust flag or no-rehash fast route.
            % Hash equality alone is not proof of another run/owner or link.
            id='RF:TXRadiationExecution';
            obj.checkEndpoint(transmitterID); a=obj.Installation;
            assert(isa(stream,'sixgr.rf.runtime.RFImpairmentStream')&&isscalar(stream)&& ...
                stream==obj.RFStream&&~stream.Faulted&&string(stream.Chain.Endpoint)=="tx"&& ...
                string(stream.Chain.Direction)==a.Direction&&stream.NumAntennas==a.PhysicalChainCount&& ...
                stream.SampleRateHz==a.SampleRateHz&&stream.ConfigurationEpoch==a.PhysicalConfigurationEpoch, ...
                'RF:TXRadiationOwnerMismatch','Use the original installed TX RF instance.');
            assert(isa(input,'sixgr.phy.waveform.WaveformChunk')&&isscalar(input),id, ...
                'Use the original RF input chunk, not prepared intent.');
            first=input.StartSample; stop=input.EndSample+1; x=input.Samples;
            assert(isfloat(x)&&ismatrix(x)&&~isempty(x)&&all(isfinite(x),'all')&& ...
                size(x,2)==a.PhysicalChainCount&&first>=a.RFStreamOriginSample&& ...
                first==fix(first)&&stop==first+size(x,1),id,'Invalid original input interval.');
            assert(isstruct(actual)&&isscalar(actual)&& ...
                all(isfield(actual,{'ExecutionStage','Config','Waveform','Chunk','Replay'}))&& ...
                string(actual.ExecutionStage)=="actual_retained_rf_stream"&& ...
                isequaln(actual.Config,stream.Chain)&& ...
                isa(actual.Chunk,'sixgr.phy.waveform.WaveformChunk')&& ...
                actual.Chunk.StartSample==first&&actual.Chunk.EndSample+1==stop&& ...
                isequaln(actual.Waveform,actual.Chunk.Samples)&&isequal(size(actual.Waveform),size(x))&& ...
                isfloat(actual.Waveform)&&all(isfinite(actual.Waveform),'all')&& ...
                stream.NextSampleIndex==stop,id, ...
                'Bind immediately after the successful original full-interval RF call.');
            r=actual.Replay;
            fields={'RFProcessingMode','RFStreamStartSample','RFStreamEndSampleExclusive', ...
                'RFConfigurationEpoch','RFInputWaveformSHA256','RFOutputWaveformSHA256', ...
                'TXSpatialPowerEnabled','TXSpatialPower','WaveformAmplitudeUnit'};
            assert(isstruct(r)&&isscalar(r)&&all(isfield(r,fields))&& ...
                string(r.RFProcessingMode)=="retained_sample_stream"&& ...
                r.RFStreamStartSample==first&&r.RFStreamEndSampleExclusive==stop&& ...
                r.RFConfigurationEpoch==a.PhysicalConfigurationEpoch&& ...
                isequal(r.TXSpatialPowerEnabled,true)&&string(r.WaveformAmplitudeUnit)==a.WaveformAmplitudeUnit,id, ...
                'Require the original RF and actual post-RF spatial-power receipt.');
            power=sixgr.rf.PowerContext(stream.Configuration,a.Direction);
            assert(string(power.WaveformAmplitudeUnit)==a.WaveformAmplitudeUnit, ...
                'RF:RadiationAbsolutePowerRequired','The owner amplitude convention changed.');
            assert(string(r.RFInputWaveformSHA256)==sixgr.rf.waveformSHA256(complex(real(x),imag(x)))&& ...
                string(r.RFOutputWaveformSHA256)==sixgr.rf.waveformSHA256(actual.Waveform), ...
                'RF:TXRadiationWaveformMismatch','Original input/output waveform hashes do not match.');
            measured=sixgr.rf.measurePhysicalTXSpatialPower(actual.Waveform);
            assert(isequaln(r.TXSpatialPower,measured), ...
                'RF:TXRadiationCovarianceMismatch', ...
                'Retained covariance must be from these original post-RF samples, including cross terms.');
            modeled=sixgr.rf.integrateRadiatedSpatialPower(measured,obj.Field,a.WaveformAmplitudeUnit);
            receipt=struct('Contract',"sixgr.executed_TX_radiation_binding/v1", ...
                'InstallationSHA256',a.InstallationSHA256,'FieldSHA256',a.FieldIdentity.FieldSHA256, ...
                'TransmitterID',a.TransmitterID,'Direction',a.Direction, ...
                'StartSample',first,'EndSampleExclusive',stop,'SampleCount',size(x,1), ...
                'SampleRateHz',a.SampleRateHz,'PhysicalConfigurationEpoch',a.PhysicalConfigurationEpoch, ...
                'PhysicalChainCount',a.PhysicalChainCount,'WaveformAmplitudeUnit',a.WaveformAmplitudeUnit, ...
                'RFInputWaveformSHA256',string(r.RFInputWaveformSHA256), ...
                'RFOutputWaveformSHA256',string(r.RFOutputWaveformSHA256), ...
                'SpatialMatrixSHA256',measured.MatrixSHA256, ...
                'InternalMeanSquare_mW',measured.TotalMeanSquare, ...
                'ModelTRP_mW',modeled.ModelTRP_mW, ...
                'SampledPeakModelEIRP_mW',modeled.SampledPeakModelEIRP_mW, ...
                'ModelResultSHA256',sixgr.rf.InstalledTXRadiationBinding.digest(modeled), ...
                'CoordinateFrame',a.CoordinateFrame,'FrequencyScope',a.FrequencyScope, ...
                'Source',"original_TX_RF_samples_independently_rechecked_component_binding", ...
                'ReferencePlane',modeled.ReferencePlane, ...
                'InternalSamplePowerIsAcceptedFeedPower',false, ...
                'OriginalRFIntervalVerified',true,'ProductionOwnerIntegrationVerified',false, ...
                'NativeChannelExecutionQualified',false,'AcceptedFeedPowerQualified',false, ...
                'HardwareConformanceVerified',false,'PowerRenormalizationApplied',false);
            receipt.ReceiptSHA256=sixgr.rf.InstalledTXRadiationBinding.digest(receipt);
        end
    end
    methods (Access=private)
        function obj=InstalledTXRadiationBinding()
        end
        function checkEndpoint(obj,endpoint)
            assert(sixgr.rf.InstalledTXRadiationBinding.text(endpoint,'RF:TXRadiationEndpointMismatch')== ...
                obj.Installation.TransmitterID,'RF:TXRadiationEndpointMismatch', ...
                'Never relabel the original installed transmitter endpoint.');
        end
    end
    methods (Static,Access=private)
        function g=geometry(a,m,role)
            id='RF:TXRadiationInstallation';
            fields={'ArrayObj','NumElements','Fc_Hz','ElementPositions_m','ElementOrderingSource', ...
                'PanelIndexByElement','PolarizationIndexByElement','PolarizationAngles_deg','BoresightAzElSlant_deg'};
            assert(isstruct(a)&&isscalar(a)&&all(isfield(a,fields))&& ...
                isa(a.ArrayObj,'phased.NRRectangularPanelArray')&&isscalar(a.ArrayObj),id, ...
                'Retain the original installed native NR panel and its explicit element descriptor.');
            n=a.NumElements; sixgr.rf.InstalledTXRadiationBinding.integer(n,1,id);
            assert(isnumeric(a.Fc_Hz)&&isreal(a.Fc_Hz)&&isscalar(a.Fc_Hz)&& ...
                isfinite(a.Fc_Hz)&&a.Fc_Hz>0,id,'Require installed carrier frequency.');
            positions=double(getElementPosition(a.ArrayObj).');
            assert(double(getNumElements(a.ArrayObj))==n&&isequal(size(positions),[n 3])&& ...
                all(isfinite(positions),'all')&&isequal(positions,double(a.ElementPositions_m)),id, ...
                'Installed native physical-element order must equal its retained descriptor.');
            panel=sixgr.rf.InstalledTXRadiationBinding.indices(a.PanelIndexByElement,n,id);
            pol=sixgr.rf.InstalledTXRadiationBinding.indices(a.PolarizationIndexByElement,n,id);
            angles=double(a.PolarizationAngles_deg(:).');
            assert(isreal(angles)&&~isempty(angles)&&all(isfinite(angles))&& ...
                all(pol<=numel(angles))&&isprop(a.ArrayObj,'ElementSet')&& ...
                isprop(a.ArrayObj,'EnablePanelSubarray')&&~a.ArrayObj.EnablePanelSubarray,id, ...
                'Require actual uncombined native physical elements and polarization order.');
            elements=a.ArrayObj.ElementSet;
            assert(iscell(elements)&&isrow(elements)&&numel(elements)==numel(angles),id, ...
                'ElementSet order must match installed polarization metadata.');
            % Native R2026a getElementPosition/getPanelArray order is panel,
            % then ElementSet, then the panel's column-major elements.
            % Check the retained index vectors, not only co-located positions.
            shape=double(a.ArrayObj.Size); perPanel=prod(shape(1:2));
            panels=prod(shape(3:4)); polCount=numel(elements);
            expectedPol=repmat(repelem(1:polCount,perPanel),1,panels);
            expectedPanel=repelem(1:panels,perPanel*polCount);
            assert(isequal(pol,expectedPol)&&isequal(panel,expectedPanel),id, ...
                'Retained panel/polarization indices must match the native physical column order.');
            for k=1:numel(elements)
                assert(isPolarizationCapable(elements{k})&&isprop(elements{k},'PolarizationAngle')&& ...
                    double(elements{k}.PolarizationAngle)==angles(k),id, ...
                    'Native polarized element orientation must equal the installed descriptor.');
            end
            boresight=double(a.BoresightAzElSlant_deg(:).');
            assert(numel(boresight)==3&&isreal(boresight)&&all(isfinite(boresight)),id,'Retain element boresight.');
            names=["Azimuth_deg","Heading_deg","Tilt_deg","PositionX_m","PositionY_m","PositionZ_m", ...
                "BoresightAzimuth_deg","BoresightElevation_deg","BoresightSlant_deg"];
            assert(isstruct(m)&&isscalar(m)&&all(isfield(m,names)),id,'Retain original endpoint installation metadata.');
            endpoint=struct();
            for name=names
                value=m.(name);
                assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&~isinf(value),id,'Invalid installation coordinate.');
                endpoint.(name)=double(value);
            end
            assert(all(isfinite([endpoint.Tilt_deg endpoint.PositionX_m endpoint.PositionY_m endpoint.PositionZ_m]))&& ...
                ((role=="bs"&&isfinite(endpoint.Azimuth_deg))|| ...
                 (role=="ue"&&isfinite(endpoint.Heading_deg))),id,'Retain active endpoint orientation.');
            assert(isequal(boresight,[endpoint.BoresightAzimuth_deg ...
                endpoint.BoresightElevation_deg endpoint.BoresightSlant_deg]),id, ...
                'Original endpoint metadata and array element boresight must agree.');
            azimuth=endpoint.Azimuth_deg; if role=="ue", azimuth=endpoint.Heading_deg; end
            orientation=[azimuth+boresight(1);endpoint.Tilt_deg-boresight(2);boresight(3)];
            native=sixgr.rf.InstalledTXRadiationBinding.nativeDefinition(a.ArrayObj,0);
            g=struct('NumPhysicalElements',double(n),'CarrierFrequencyHz',double(a.Fc_Hz), ...
                'ElementPositions_m',positions,'PanelIndexByElement',panel, ...
                'PolarizationIndexByElement',pol,'PolarizationAngles_deg',angles, ...
                'ElementBoresightAzElSlant_deg',boresight,'EndpointInstallation',endpoint, ...
                'NativeArrayOrientation_deg',orientation, ...
                'ElementOrderingSource',sixgr.rf.InstalledTXRadiationBinding.text(a.ElementOrderingSource,id), ...
                'NativeDefinition',native,'NativeDefinitionSHA256',sixgr.rf.InstalledTXRadiationBinding.digest(native), ...
                'Coordinates',"native_installed_local_element_order_not_global_rotated_positions");
        end
        function d=nativeDefinition(value,depth)
            % All public native properties, recursively including ElementSet.
            % Hash numeric property contents losslessly (including shape and
            % class); never compare handles or positions alone. Unsupported
            % property types fail closed instead of silently omitting them.
            id='RF:TXRadiationNativeDefinition';
            assert(depth<8,id,'Unsupported recursive native array definition.');
            d=struct('Class',string(class(value)),'Size',double(size(value)));
            if isnumeric(value)||islogical(value)
                d.NumericSHA256=sixgr.phy.waveform.WaveformHash.runtimeArray(value);
            elseif ischar(value)||isstring(value)
                assert(~any(ismissing(string(value)),'all'),id,'Missing native text property.');
                d.Text=value;
            elseif iscell(value)
                d.Values=cell(size(value));
                for k=1:numel(value)
                    d.Values{k}=sixgr.rf.InstalledTXRadiationBinding.nativeDefinition(value{k},depth+1);
                end
            elseif isstruct(value)&&isscalar(value)
                names=sort(string(fieldnames(value))); d.Properties=struct();
                for name=reshape(names,1,[])
                    d.Properties.(name)=sixgr.rf.InstalledTXRadiationBinding.nativeDefinition(value.(name),depth+1);
                end
            elseif isobject(value)&&isscalar(value)
                names=sort(string(properties(value))); d.Properties=struct();
                for name=reshape(names,1,[])
                    d.Properties.(name)=sixgr.rf.InstalledTXRadiationBinding.nativeDefinition(value.(name),depth+1);
                end
            else
                error(id,'Unsupported native property type %s; do not invent equivalence.',class(value));
            end
        end
        function f=fieldIdentity(field)
            f=rmfield(field,{'H','V','SolidAngle_sr','AzimuthElevation_deg'});
            f.HSHA256=sixgr.phy.waveform.WaveformHash.runtimeArray(field.H);
            f.VSHA256=sixgr.phy.waveform.WaveformHash.runtimeArray(field.V);
            f.WeightsSHA256=sixgr.phy.waveform.WaveformHash.runtimeArray(field.SolidAngle_sr);
            f.DirectionsSHA256=sixgr.phy.waveform.WaveformHash.runtimeArray(field.AzimuthElevation_deg);
            f.FieldSHA256=sixgr.rf.InstalledTXRadiationBinding.digest(f);
        end
        function value=indices(value,n,id)
            assert(isnumeric(value)&&isreal(value)&&isvector(value)&&numel(value)==n&& ...
                all(isfinite(value(:)))&&all(value(:)>=1&value(:)==fix(value(:))),id,'Invalid installed index order.');
            value=double(value(:).');
        end
        function integer(value,minimum,id)
            assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value)&& ...
                value==fix(value)&&value>=minimum,id,'Require an exact finite integer.');
        end
        function value=text(value,id)
            assert((ischar(value)||isstring(value))&&isscalar(string(value))&& ...
                ~ismissing(string(value))&&strlength(strtrim(string(value)))>0,id,'Require explicit scalar text.');
            value=string(value);
        end
        function sha=digest(value)
            sha=string(sixgr.util.sha256Hex(unicode2native(jsonencode(value),'UTF-8')));
        end
    end
