function tf = isFixedSNRLinkAuthority(cfg)
%ISFIXEDSNRLINKAUTHORITY True when configured occupied-RE SNR owns noise.
tf = upper(strtrim(string(sixgr.util.structGet( ...
    cfg, "integration.run_mode", "")))) == "FIXED_SNR_SWEEP" && ...
    logical(sixgr.util.structGet(cfg, ...
    "integration.configured_snr_is_link_authority", false));
tf = logical(tf);
end
