classdef RFSpecificationTableRegistry
%RFSPECIFICATIONTABLEREGISTRY Pinned RF/PHY specification baseline.
%   Only rows with ENABLED status may back an emulation profile. The
%   radiated BS method remains disabled until an exact table pack exists.

    methods(Static)
        function baseline=baseline()
            baseline=struct( ...
                "TS_38_101_1","V19.4.0", ...
                "TS_38_101_2","V19.4.0", ...
                "TS_38_104","V19.4.0", ...
                "TS_38_141_1","V19.4.0", ...
                "TS_38_141_2","SPEC_LOOKUP_REQUIRED", ...
                "TS_38_521_1","V19.4.0", ...
                "TS_38_521_2","V19.2.0", ...
                "TS_38_211","V18.8.0", ...
                "TS_38_212","V18.8.0", ...
                "TS_38_213","V18.8.0", ...
                "TS_38_214","V18.9.0", ...
                "TS_38_215","V18.8.0", ...
                "TS_38_331","V18.9.0", ...
                "RegistryVersion","6GR-RF-TABLES-1.0.0");
        end

        function row=resolve(tableId)
            token=upper(strtrim(string(tableId)));
            baseline=sixgr.rf.runtime.RFSpecificationTableRegistry.baseline();
            switch token
                case "BS_FR1_CONDUCTED_V19_4"
                    row=sixgr.rf.runtime.RFSpecificationTableRegistry.row( ...
                        token,"3GPP TS 38.104",baseline.TS_38_104, ...
                        "3GPP TS 38.141-1",baseline.TS_38_141_1, ...
                        "CONDUCTED","ENABLED");
                case "UE_FR1_CONDUCTED_V19_4"
                    row=sixgr.rf.runtime.RFSpecificationTableRegistry.row( ...
                        token,"3GPP TS 38.101-1",baseline.TS_38_101_1, ...
                        "3GPP TS 38.521-1",baseline.TS_38_521_1, ...
                        "CONDUCTED","ENABLED");
                case "UE_FR2_CONDUCTED_V19_2"
                    row=sixgr.rf.runtime.RFSpecificationTableRegistry.row( ...
                        token,"3GPP TS 38.101-2",baseline.TS_38_101_2, ...
                        "3GPP TS 38.521-2",baseline.TS_38_521_2, ...
                        "CONDUCTED","ENABLED");
                case "BS_FR2_RADIATED_PENDING"
                    row=sixgr.rf.runtime.RFSpecificationTableRegistry.row( ...
                        token,"3GPP TS 38.104",baseline.TS_38_104, ...
                        "3GPP TS 38.141-2","SPEC_LOOKUP_REQUIRED", ...
                        "RADIATED","SPEC_LOOKUP_REQUIRED");
                otherwise
                    error("RF:SpecificationTableUnavailable", ...
                        "RF specification table '%s' is not frozen in this repository.", ...
                        token);
            end
        end

        function requireEnabled(tableId)
            row=sixgr.rf.runtime.RFSpecificationTableRegistry.resolve(tableId);
            if string(row.Status)~="ENABLED"
                error("RF:SpecificationTableUnavailable", ...
                    "RF specification table '%s' is not enabled.",tableId);
            end
        end

        function rows=allRows()
            ids=["BS_FR1_CONDUCTED_V19_4";"UE_FR1_CONDUCTED_V19_4"; ...
                "UE_FR2_CONDUCTED_V19_2";"BS_FR2_RADIATED_PENDING"];
            rows=repmat(sixgr.rf.runtime.RFSpecificationTableRegistry. ...
                resolve(ids(1)),numel(ids),1);
            for k=1:numel(ids)
                rows(k)=sixgr.rf.runtime.RFSpecificationTableRegistry.resolve(ids(k));
            end
        end
    end

    methods(Static,Access=private)
        function value=row(id,requirement,requirementVersion,method, ...
                methodVersion,referenceType,status)
            value=struct("TableRegistryID",string(id), ...
                "RequirementSpecification",string(requirement), ...
                "RequirementVersion",string(requirementVersion), ...
                "MethodSpecification",string(method), ...
                "MethodVersion",string(methodVersion), ...
                "ReferenceType",string(referenceType), ...
                "Status",string(status), ...
                "PermittedClaim","EMULATION_ONLY");
        end
    end
end
