classdef RFSelectivityFilter
%RFSELECTIVITYFILTER Explicit stateful receive-selectivity FIR.

    methods(Static)
        function profile = validate(profile, sampleRateHz)
            required = ["ProfileID","Version","Taps","Passband_Hz", ...
                "Stopband_Hz","ENBW_Hz"];
            if ~isstruct(profile) || ~all(isfield(profile, required))
                error("RF:SelectivityFilterMissing", ...
                    "RF selectivity-filter profile is incomplete.");
            end
            taps = double(profile.Taps(:));
            bands = double([profile.Passband_Hz profile.Stopband_Hz profile.ENBW_Hz]);
            if isempty(taps) || any(~isfinite(taps)) || any(~isfinite(bands)) || ...
                    bands(1) <= 0 || bands(2) <= bands(1) || ...
                    bands(2) >= sampleRateHz/2 || bands(3) <= 0
                error("RF:SelectivityFilterMissing", ...
                    "RF selectivity-filter taps, bands or ENBW are invalid.");
            end
            profile.Taps = taps./sum(taps);
            profile.SampleRate_Hz = double(sampleRateHz);
        end

        function [output,state,evidence] = apply(input,profile,state)
            profile = sixgr.rf.runtime.RFSelectivityFilter.validate( ...
                profile,profile.SampleRate_Hz);
            if nargin<3 || isempty(state)
                state=zeros(numel(profile.Taps)-1,size(input,2));
            end
            [output,state,~]=sixgr.rf.runtime.ReconstructionFilter.apply( ...
                input,struct("ProfileID",profile.ProfileID, ...
                "Version",profile.Version,"Taps",profile.Taps, ...
                "Passband_Hz",profile.Passband_Hz, ...
                "Stopband_Hz",profile.Stopband_Hz, ...
                "SampleRate_Hz",profile.SampleRate_Hz),state);
            evidence=struct("ProfileID",string(profile.ProfileID), ...
                "ENBW_Hz",double(profile.ENBW_Hz), ...
                "TapCount",numel(profile.Taps), ...
                "ReferencePlane","POST_SELECTIVITY_FILTER");
        end
    end
end
