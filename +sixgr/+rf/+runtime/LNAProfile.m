classdef LNAProfile
%LNAPROFILE Explicit gain, noise figure and compression model.

    methods(Static)
        function profile = validate(profile)
            required = ["ProfileID","Version","Gain_dB","NoiseFigure_dB", ...
                "P1dBInput_dBm","ReferenceImpedance_Ohm"];
            if ~isstruct(profile) || ~all(isfield(profile, required))
                error("RF:LNAProfileMissing", ...
                    "LNA profile is incomplete.");
            end
            values = double([profile.Gain_dB profile.NoiseFigure_dB ...
                profile.P1dBInput_dBm profile.ReferenceImpedance_Ohm]);
            if any(~isfinite(values)) || profile.NoiseFigure_dB < 0 || ...
                    profile.ReferenceImpedance_Ohm <= 0
                error("RF:LNAProfileMissing", ...
                    "LNA gain, NF, P1dB and impedance must be explicit and finite.");
            end
        end

        function [output, evidence] = apply(input, profile, inputPower_dBm)
            profile = sixgr.rf.runtime.LNAProfile.validate(profile);
            if isempty(input) || any(~isfinite(input(:))) || ...
                    ~(isscalar(inputPower_dBm) && isfinite(inputPower_dBm))
                error("RF:NonFiniteSamples", ...
                    "LNA execution requires finite waveform and input power.");
            end
            linearGain = 10^(double(profile.Gain_dB)/20);
            compression = max(0, double(inputPower_dBm)- ...
                double(profile.P1dBInput_dBm));
            appliedGain_dB = double(profile.Gain_dB)-compression;
            output = input .* cast(10^(appliedGain_dB/20),"like",input);
            evidence = struct("ProfileID",string(profile.ProfileID), ...
                "AppliedGain_dB",appliedGain_dB, ...
                "NominalLinearGain",linearGain, ...
                "Compression_dB",compression, ...
                "NoiseFigure_dB",double(profile.NoiseFigure_dB), ...
                "ReferencePlane","LNA_OUTPUT");
        end
    end
end
