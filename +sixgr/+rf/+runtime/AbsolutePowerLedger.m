classdef AbsolutePowerLedger
%ABSOLUTEPOWERLEDGER Sample-domain power measurement and stage closure.

    methods(Static)
        function measurement = measure(samples, impedanceOhm, referencePlane, bandwidthHz)
            if nargin < 4
                bandwidthHz = NaN;
            end
            plane = sixgr.rf.runtime.RFReferencePlane.validate(referencePlane);
            impedanceOhm = double(impedanceOhm);
            if ~(isscalar(impedanceOhm) && isfinite(impedanceOhm) && impedanceOhm > 0)
                error("RF:MissingPowerParameter", ...
                    "A positive finite reference impedance is required.");
            end
            if isempty(samples) || ~isnumeric(samples) || any(~isfinite(samples(:)))
                error("RF:NonFiniteSamples", ...
                    "Power measurement requires finite nonempty samples.");
            end
            perPort_mW = mean(abs(double(samples)).^2, 1);
            total_mW = sum(perPort_mW);
            measurement = struct( ...
                "ReferencePlane", plane, ...
                "Impedance_Ohm", impedanceOhm, ...
                "Bandwidth_Hz", double(bandwidthHz), ...
                "PerPortPower_mW", perPort_mW, ...
                "TotalPower_mW", total_mW, ...
                "TotalPower_dBm", 10 * log10(max(total_mW, realmin)), ...
                "PeakPower_mW", max(sum(abs(double(samples)).^2, 2)), ...
                "PAPR_dB", 10 * log10(max(max(sum(abs(double(samples)).^2, 2)), ...
                    realmin) / max(total_mW, realmin)), ...
                "SampleUnit", "sqrt_mW");
        end

        function stage = applyStage(inputMeasurement, gain_dB, loss_dB, ...
                nonlinearPowerChange_dB, outputPlane)
            gain_dB = sixgr.rf.runtime.AbsolutePowerLedger.finiteScalar( ...
                gain_dB, "gain");
            loss_dB = sixgr.rf.runtime.AbsolutePowerLedger.finiteScalar( ...
                loss_dB, "loss");
            nonlinearPowerChange_dB = ...
                sixgr.rf.runtime.AbsolutePowerLedger.finiteScalar( ...
                nonlinearPowerChange_dB, "nonlinear power change");
            outputPlane = sixgr.rf.runtime.RFReferencePlane.validate(outputPlane);
            stage = struct( ...
                "InputReferencePlane", string(inputMeasurement.ReferencePlane), ...
                "OutputReferencePlane", outputPlane, ...
                "InputPower_dBm", double(inputMeasurement.TotalPower_dBm), ...
                "Gain_dB", gain_dB, ...
                "Loss_dB", loss_dB, ...
                "NonlinearPowerChange_dB", nonlinearPowerChange_dB, ...
                "ExpectedOutputPower_dBm", double(inputMeasurement.TotalPower_dBm) + ...
                    gain_dB - loss_dB + nonlinearPowerChange_dB);
        end
    end

    methods(Static, Access=private)
        function value = finiteScalar(raw, name)
            value = double(raw);
            if ~(isscalar(value) && isfinite(value))
                error("RF:MissingPowerParameter", ...
                    "RF stage %s must be a finite scalar.", name);
            end
        end
    end
end
