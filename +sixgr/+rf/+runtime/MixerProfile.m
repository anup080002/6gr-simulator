classdef MixerProfile
%MIXERPROFILE Explicit complex downconversion and bounded nonlinearity.

    methods(Static)
        function [output, evidence] = apply(input, sampleRateHz, profile, ...
                sampleIndex)
            required = ["ProfileID","Version","LOFrequency_Hz", ...
                "ConversionGain_dB","NoiseFigure_dB","IIP2_dBm","IIP3_dBm"];
            if ~isstruct(profile) || ~all(isfield(profile, required)) || ...
                    ~(isscalar(sampleRateHz) && isfinite(sampleRateHz) && ...
                    sampleRateHz > 0) || ~(isscalar(sampleIndex) && ...
                    isfinite(sampleIndex) && sampleIndex >= 0)
                error("RF:MixerProfileMissing", ...
                    "Mixer execution requires an explicit versioned profile.");
            end
            values = double([profile.LOFrequency_Hz profile.ConversionGain_dB ...
                profile.NoiseFigure_dB profile.IIP2_dBm profile.IIP3_dBm]);
            if any(~isfinite(values)) || profile.NoiseFigure_dB<0 || ...
                    any(~isfinite(input(:)))
                error("RF:MixerProfileMissing", ...
                    "Mixer profile and waveform must be finite.");
            end
            n = sampleIndex+(0:size(input,1)-1).';
            lo = exp(-1j*2*pi*double(profile.LOFrequency_Hz)*n/sampleRateHz);
            mixed = double(input).*lo;
            a2 = 10^(-double(profile.IIP2_dBm)/20);
            a3 = 10^(-double(profile.IIP3_dBm)/10);
            nonlinear = mixed + a2.*mixed.^2 + a3.*mixed.*abs(mixed).^2;
            output = nonlinear .* 10^(double(profile.ConversionGain_dB)/20);
            output = cast(output,"like",input);
            evidence = struct("ProfileID",string(profile.ProfileID), ...
                "LOFrequency_Hz",double(profile.LOFrequency_Hz), ...
                "ConversionGain_dB",double(profile.ConversionGain_dB), ...
                "NoiseFigure_dB",double(profile.NoiseFigure_dB), ...
                "IIP2_dBm",double(profile.IIP2_dBm), ...
                "IIP3_dBm",double(profile.IIP3_dBm), ...
                "NextSampleIndex",sampleIndex+size(input,1), ...
                "ReferencePlane","MIXER_OUTPUT");
        end
    end
end
