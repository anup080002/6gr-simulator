classdef RFStateTrace
%RFSTATETRACE Immutable state-transition evidence row.

    methods(Static)
        function row = record(stageName, stateId, epoch, sampleStart, ...
                sampleEnd, inputHash, outputHash, appliedParameters)
            names = string({stageName, stateId, inputHash, outputHash});
            if any(strlength(strtrim(names)) == 0) || ...
                    ~(isscalar(epoch) && isfinite(epoch)) || ...
                    ~(isscalar(sampleStart) && isfinite(sampleStart)) || ...
                    ~(isscalar(sampleEnd) && isfinite(sampleEnd) && ...
                    sampleEnd >= sampleStart) || ~isstruct(appliedParameters)
                error("RF:StateTraceInvalid", ...
                    "RF state traces require explicit IDs, hashes, epoch and sample interval.");
            end
            row = struct( ...
                "Stage", string(stageName), ...
                "StateID", string(stateId), ...
                "StateEpoch", double(epoch), ...
                "SampleStart", double(sampleStart), ...
                "SampleEnd", double(sampleEnd), ...
                "InputSHA256", string(inputHash), ...
                "OutputSHA256", string(outputHash), ...
                "AppliedParameters", appliedParameters);
        end

        function digest = sampleHash(samples)
            if isempty(samples) || any(~isfinite(samples(:)))
                error("RF:NonFiniteSamples", ...
                    "RF state hashing requires finite nonempty samples.");
            end
            payload = [typecast(real(double(samples(:))), "uint8") ...
                typecast(imag(double(samples(:))), "uint8")];
            digest = string(sixgr.util.sha256Hex(payload(:)));
        end
    end
end
