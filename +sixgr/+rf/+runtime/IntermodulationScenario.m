classdef IntermodulationScenario
%INTERMODULATIONSCENARIO Two-tone sample-domain IM2/IM3 experiment.

    methods(Static)
        function result = run(sampleRateHz, sampleCount, profile)
            required=["Tone1_Hz","Tone2_Hz","TonePower_dBm", ...
                "IIP2_dBm","IIP3_dBm","Seed"];
            if ~isstruct(profile)||~all(isfield(profile,required)) || ...
                    ~(isscalar(sampleRateHz)&&isfinite(sampleRateHz)&& ...
                    sampleRateHz>0) || ~(isscalar(sampleCount)&& ...
                    sampleCount==round(sampleCount)&&sampleCount>=256)
                error("RF:IntermodulationProfileMissing", ...
                    "Intermodulation scenario is incomplete.");
            end
            f1=double(profile.Tone1_Hz); f2=double(profile.Tone2_Hz);
            if any(~isfinite([f1 f2 profile.TonePower_dBm ...
                    profile.IIP2_dBm profile.IIP3_dBm])) || ...
                    max(abs([f1 f2]))>=sampleRateHz/2 || f1==f2
                error("RF:IntermodulationProfileMissing", ...
                    "Intermodulation tones or intercept points are invalid.");
            end
            n=(0:sampleCount-1).';
            amplitude=sqrt(10^(double(profile.TonePower_dBm)/10));
            x=amplitude*(exp(1j*2*pi*f1*n/sampleRateHz)+ ...
                exp(1j*2*pi*f2*n/sampleRateHz));
            a2=10^(-double(profile.IIP2_dBm)/20);
            a3=10^(-double(profile.IIP3_dBm)/10);
            y=x+a2*x.^2+a3*x.*abs(x).^2;
            result=struct("Input",x,"Output",y, ...
                "IM2Frequencies_Hz",[f1+f2 abs(f1-f2)], ...
                "IM3Frequencies_Hz",[2*f1-f2 2*f2-f1], ...
                "ExpectedIM2Power_dBm",2*double(profile.TonePower_dBm)- ...
                double(profile.IIP2_dBm), ...
                "ExpectedIM3Power_dBm",3*double(profile.TonePower_dBm)- ...
                2*double(profile.IIP3_dBm), ...
                "Source","sample_domain_two_tone_nonlinearity");
        end
    end
end
