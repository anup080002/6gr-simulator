classdef ACLRMeasurement
%ACLRMEASUREMENT Filtered assigned/adjacent-channel power measurement.

    methods(Static)
        function result=measure(samples,sampleRateHz,profile)
            required=["FilterID","AssignedCenter_Hz","AdjacentOffset_Hz", ...
                "MeasurementBandwidth_Hz"];
            if ~isstruct(profile)||~all(isfield(profile,required))
                error("RF:ACLRFilterInvalid", ...
                    "ACLR measurement requires an explicit filter profile.");
            end
            if ~isnumeric(samples)||~ismatrix(samples)||isempty(samples)|| ...
                    any(~isfinite(samples(:)))||~isscalar(sampleRateHz)|| ...
                    ~isreal(sampleRateHz)||~isfinite(sampleRateHz)||sampleRateHz<=0
                error("RF:ACLRFilterInvalid","ACLR waveform/sample rate is invalid.");
            end
            % A waveform matrix is time-by-port, never concatenated ports.
            if isvector(samples), samples=samples(:); end
            sampleCount=size(samples,1);
            n=max(4096,2^nextpow2(sampleCount));
            spectrum=fftshift(fft(double(samples),n,1),1);
            % Parseval normalization uses observation length, not padded FFT
            % length twice. Zero padding must not change measured power.
            power=abs(spectrum).^2/(n*sampleCount);
            frequency=(-n/2:n/2-1).'*double(sampleRateHz)/n;
            bandwidth=double(profile.MeasurementBandwidth_Hz);
            center=double(profile.AssignedCenter_Hz);
            offset=double(profile.AdjacentOffset_Hz);
            if ~(isscalar(bandwidth)&&isreal(bandwidth)&&isfinite(bandwidth)&&bandwidth>0&& ...
                    isscalar(center)&&isreal(center)&&isfinite(center)&& ...
                    isscalar(offset)&&isreal(offset)&&isfinite(offset)&&offset>bandwidth/2)
                error("RF:ACLRFilterInvalid","ACLR band definition is invalid.");
            end
            centers=[center center-offset center+offset];
            if any(abs(centers)+bandwidth/2>double(sampleRateHz)/2)
                error("RF:ACLRFilterInvalid", ...
                    "Complete assigned and adjacent measurement filters must fit within the sampled bandwidth; increase the waveform sample rate.");
            end
            assigned=sixgr.rf.runtime.ACLRMeasurement.bandPower( ...
                power,frequency,center,bandwidth);
            lower=sixgr.rf.runtime.ACLRMeasurement.bandPower( ...
                power,frequency,center-offset,bandwidth);
            upper=sixgr.rf.runtime.ACLRMeasurement.bandPower( ...
                power,frequency,center+offset,bandwidth);
            result=struct( ...
                "AssignedPower_dB",10*log10(assigned), ...
                "AdjacentLowerPower_dB",10*log10(lower), ...
                "AdjacentUpperPower_dB",10*log10(upper), ...
                "ACLRLower_dB",10*log10(assigned./lower), ...
                "ACLRUpper_dB",10*log10(assigned./upper), ...
                "HasAssignedPower",assigned>0, ...
                "SumPortACLRLower_dB",10*log10(sum(assigned)/sum(lower)), ...
                "SumPortACLRUpper_dB",10*log10(sum(assigned)/sum(upper)), ...
                "AssignedPower",assigned,"AdjacentLowerPower",lower,"AdjacentUpperPower",upper, ...
                "TotalCapturedPower",mean(abs(double(samples)).^2,1), ...
                "IntegratedSpectrumPower",sum(power,1), ...
                "PowerUnit","input_amplitude_squared_not_implicitly_watts", ...
                "PowerDBReference","one_input_amplitude_squared", ...
                "CaptureSampleCount",sampleCount,"NumPorts",size(samples,2), ...
                "SampleRateHz",double(sampleRateHz),"Nfft",n, ...
                "AssignedCenter_Hz",center,"AdjacentOffset_Hz",offset, ...
                "MeasurementBandwidth_Hz",bandwidth, ...
                "FilterID",string(profile.FilterID), ...
                "Method","fft_integrated_explicit_rectangular_filter");
        end
    end

    methods(Static,Access=private)
        function value=bandPower(power,frequency,center,bandwidth)
            % Half-open bands avoid double counting a shared boundary bin.
            mask=frequency>=center-bandwidth/2 & frequency<center+bandwidth/2;
            if ~any(mask)
                error("RF:ACLRFilterInvalid", ...
                    "ACLR filter has no FFT bins at the selected sample rate.");
            end
            value=sum(power(mask,:),1);
        end
    end
end
