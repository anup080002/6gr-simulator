classdef DPDProfile
%DPDPROFILE Versioned predistorter coefficient validation.

    methods(Static)
        function profile = validate(profile)
            required = ["ProfileID","Version","Model","Coefficients", ...
                "Orders","MemoryDepth","TrainingWaveformSHA256", ...
                "HoldoutWaveformSHA256"];
            if ~isstruct(profile) || ~all(isfield(profile, required))
                error("RF:DPDProfileMissing", ...
                    "DPD requires a versioned coefficient and waveform profile.");
            end
            coefficients = profile.Coefficients;
            orders = double(profile.Orders(:));
            memoryDepth = double(profile.MemoryDepth);
            if ~isnumeric(coefficients) || any(~isfinite(coefficients(:))) || ...
                    isempty(orders) || any(~isfinite(orders)) || ...
                    ~(isscalar(memoryDepth) && isfinite(memoryDepth) && ...
                    memoryDepth == round(memoryDepth) && memoryDepth >= 1) || ...
                    string(profile.TrainingWaveformSHA256) == ...
                    string(profile.HoldoutWaveformSHA256)
                error("RF:DPDProfileMissing", ...
                    "DPD coefficients, dimensions or independent holdout identity are invalid.");
            end
            bytes=typecast([real(double(coefficients(:))); ...
                imag(double(coefficients(:)))],"uint8");
            profile.CoefficientSHA256 = string(sixgr.util.sha256Hex(bytes));
        end
    end
end
