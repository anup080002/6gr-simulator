function [trainingT,validationT]=localDPD(root,seeds)
input=localRead(fullfile(root,"rf_dpd_cfr_test_vectors.csv"));
n=max(50,height(input));
trainRows=repmat(struct("CaseID","","PAProfile","","DPDProfile","", ...
    "TrainingSamples",0,"Order",0,"MemoryDepth",0, ...
    "TrainingWaveformSHA256","","CoefficientSHA256","", ...
    "Converged",false,"Status",""),n,1);
validRows=repmat(struct("CaseID","","PAProfile","","DPDProfile","", ...
    "HoldoutSamples",0,"EVMBefore_pct",0,"EVMAfter_pct",0, ...
    "ACLRBefore_dB",0,"ACLRAfter_dB",0,"OutputPowerChange_dB",0, ...
    "HoldoutWaveformSHA256","","Status",""),n,1);
for k=1:n
    source=mod(k-1,height(input))+1;
    actualTraining=double(input.TrainingSamples(source));
    actualHoldout=double(input.HoldoutSamples(source));
    xTrain=localOFDMWaveform(actualTraining,seeds(mod(k-1,numel(seeds))+1)+k);
    xHold=localOFDMWaveform(actualHoldout,seeds(mod(k-1,numel(seeds))+1)+1000+k);
    trainingHash=sixgr.rf.runtime.RFStateTrace.sampleHash(xTrain);
    holdoutHash=sixgr.rf.runtime.RFStateTrace.sampleHash(xHold);
    profile=localPAProfile(input.PAProfile(source),0);
    [yTrain,~]=sixgr.rf.runtime.PAProfile.apply(xTrain,profile);
    model=sixgr.rf.runtime.DPDTrainer.train(xTrain,yTrain, ...
        input.DPDOrder(source),input.MemoryDepth(source), ...
        "DPD-"+string(input.CaseID(source)));
    model.Version="1.0.0";
    model.Model="memory_polynomial";
    model.TrainingWaveformSHA256=trainingHash;
    model.HoldoutWaveformSHA256=holdoutHash;
    model=sixgr.rf.runtime.DPDProfile.validate(model);
    [before,~]=sixgr.rf.runtime.PAProfile.apply(xHold,profile);
    drive=sixgr.rf.runtime.DPDTrainer.apply(xHold,model);
    [after,~]=sixgr.rf.runtime.PAProfile.apply(drive,profile);
    evmBefore=100*norm(double(before-xHold))/norm(double(xHold));
    evmAfter=100*norm(double(after-xHold))/norm(double(xHold));
    aclrBefore=localSpectralACLRResidual(before,xHold);
    aclrAfter=localSpectralACLRResidual(after,xHold);
    outputChange=10*log10(mean(abs(double(after)).^2)/ ...
        max(mean(abs(double(before)).^2),realmin));
    pass=evmAfter<=evmBefore+1e-9 && aclrAfter>=aclrBefore;
    trainRows(k)=struct("CaseID",string(input.CaseID(source)), ...
        "PAProfile",string(profile.ProfileID), ...
        "DPDProfile",string(model.ProfileID), ...
        "TrainingSamples",actualTraining,"Order",model.Order, ...
        "MemoryDepth",model.MemoryDepth, ...
