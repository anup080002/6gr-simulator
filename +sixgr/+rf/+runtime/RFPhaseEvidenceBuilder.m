classdef RFPhaseEvidenceBuilder
%RFPHASEEVIDENCEBUILDER Execute Phase-11 bounded vectors in production code.

    methods(Static)
        function evidence=build(vectorRoot,seedList,confidenceLevel)
            arguments
                vectorRoot (1,1) string
                seedList double = [11 23 47 89]
                confidenceLevel (1,1) double = 0.95
            end
            if ~isfolder(vectorRoot)
                error("RF:UnsupportedCombination","RF vector root does not exist.");
            end
            evidence=struct();
            evidence.rf_profile_resolution=localProfiles(vectorRoot);
            [evidence.rf_chain_stage_ledger,evidence.rf_reference_plane_power]= ...
                localPowerLedgers(seedList);
            [evidence.rf_cfo_acquisition,evidence.rf_cfo_tracking]= ...
                localCFO(vectorRoot);
            [evidence.rf_timing_acquisition,evidence.rf_timing_tracking]= ...
                localTiming(vectorRoot);
            evidence.rf_sco_resampler=localSCO(vectorRoot);
            [evidence.rf_phase_noise_psd,evidence.rf_phase_noise_tracking]= ...
                localPhaseNoise(vectorRoot);
            [evidence.rf_iq_imbalance,evidence.rf_iq_compensation]= ...
                localIQ(vectorRoot);
            [evidence.rf_pa_characterization,evidence.rf_pa_memory]= ...
                localPA(vectorRoot);
            [evidence.rf_dpd_training,evidence.rf_dpd_validation]= ...
                localDPD(vectorRoot,seedList);
            [evidence.rf_dac_quantization,evidence.rf_adc_quantization]= ...
                localQuantizers(vectorRoot);
            evidence.rf_agc_trace=localAGC();
            evidence.rf_noise_figure_cascade=localNoise(vectorRoot);
            [evidence.rf_blocker_trials,evidence.rf_intermodulation_trials]= ...
                localBlockers(vectorRoot);
            evidence.rf_receiver_dynamic_range=localDynamicRange();
            [evidence.rf_evm_measurement,evidence.rf_aclr_measurement, ...
                evidence.rf_sem_obue_measurement]=localWaveformQuality(vectorRoot);
            [evidence.rf_ul_power_control,evidence.rf_power_control_state]= ...
                localPowerControl(vectorRoot);
            evidence.rf_receiver_metrics=localReceiverMetrics( ...
                evidence.rf_evm_measurement,evidence.rf_cfo_acquisition, ...
                evidence.rf_timing_acquisition);
            evidence.rf_negative_tests=localNegative(vectorRoot);
            evidence.Metadata=struct("VectorRoot",vectorRoot, ...
                "SeedList",double(seedList(:).'), ...
                "ConfidenceLevel",confidenceLevel, ...
                "ExecutionBackend","sixgr.rf.runtime.production_kernels", ...
                "ClaimRestriction","NO_RF_DEVICE_CONFORMANCE");
        end
    end
end

function T=localProfiles(root)
input=localRead(fullfile(root,"rf_capability_profile_matrix.csv"));
rows=repmat(struct("CaseID","","ProfileID","","Feature","", ...
    "ExpectedOutcome","","ActualOutcome","","ClaimClass","", ...
    "Status",""),height(input),1);
for k=1:height(input)
    result=sixgr.rf.runtime.RFCapabilityProfile.resolve( ...
        input.ProfileID(k),input.Feature(k));
    rows(k)=struct("CaseID","CAP-"+compose("%04d",k), ...
        "ProfileID",string(input.ProfileID(k)), ...
        "Feature",string(input.Feature(k)), ...
        "ExpectedOutcome",upper(string(input.ExpectedOutcome(k))), ...
        "ActualOutcome",upper(string(result.ActualOutcome)), ...
        "ClaimClass",string(result.ClaimClass), ...
        "Status",localPass(upper(string(result.ActualOutcome))== ...
        upper(string(input.ExpectedOutcome(k)))));
end
T=struct2table(rows);
end

function [stageT,powerT]=localPowerLedgers(seeds)
stageNames=["digital_scaling","dac_and_reconstruction","pa_no_restoration", ...
    "antenna_connector"];
inputPlanes=["DIGITAL_LAYER_PORT","DAC_INPUT","PA_INPUT","PA_OUTPUT"];
outputPlanes=["DAC_INPUT","POST_RECONSTRUCTION_FILTER","PA_OUTPUT", ...
    "TX_ANTENNA_CONNECTOR_OR_DECLARED_TAB"];
gain=[0 -0.5 -0.25 -1.0];
stageRows=repmat(struct("RunID","","StageIndex",0,"StageName","", ...
    "Direction","","InputReferencePlane","","OutputReferencePlane","", ...
    "InputPower_dBm",0,"OutputPower_dBm",0,"StateID","", ...
    "Status",""),100,1);
powerRows=repmat(struct("RunID","","ReferencePlane","", ...
    "ExpectedPower_dBm",0,"MeasuredPower_dBm",0,"Error_dB",0, ...
    "Bandwidth_Hz",0,"Impedance_Ohm",0,"Status",""),100,1);
row=0;
for run=1:25
    seed=seeds(mod(run-1,numel(seeds))+1);
    rs=RandStream("Threefry","Seed",seed+run);
    bits=randi(rs,[0 3],2048,1);
    constellation=exp(1j*(pi/4+pi/2*bits));
    target=-20+run;
    waveform=constellation.*10^(target/20);
    stateID="RFSTATE-"+compose("%03d",run);
    for stage=1:4
        row=row+1;
        input=sixgr.rf.runtime.AbsolutePowerLedger.measure( ...
            waveform,50,inputPlanes(stage),100e6);
        expected=input.TotalPower_dBm+gain(stage);
        waveform=waveform.*10^(gain(stage)/20);
        output=sixgr.rf.runtime.AbsolutePowerLedger.measure( ...
            waveform,50,outputPlanes(stage),100e6);
        error_dB=output.TotalPower_dBm-expected;
        stageRows(row)=struct("RunID","RF-"+compose("%03d",run), ...
            "StageIndex",stage,"StageName",stageNames(stage), ...
            "Direction","TX","InputReferencePlane",inputPlanes(stage), ...
            "OutputReferencePlane",outputPlanes(stage), ...
            "InputPower_dBm",input.TotalPower_dBm, ...
            "OutputPower_dBm",output.TotalPower_dBm,"StateID",stateID, ...
            "Status",localPass(abs(error_dB)<=0.05));
        powerRows(row)=struct("RunID","RF-"+compose("%03d",run), ...
            "ReferencePlane",outputPlanes(stage), ...
            "ExpectedPower_dBm",expected, ...
            "MeasuredPower_dBm",output.TotalPower_dBm, ...
            "Error_dB",error_dB,"Bandwidth_Hz",100e6, ...
            "Impedance_Ohm",50,"Status",localPass(abs(error_dB)<=0.05));
    end
end
stageT=struct2table(stageRows); powerT=struct2table(powerRows);
end

