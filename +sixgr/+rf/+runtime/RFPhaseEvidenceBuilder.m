function x=localOFDMWaveform(count,seed)
rs=RandStream("Threefry","Seed",double(seed));
nfft=256; occupied=64; blocks=ceil(count/nfft);
grid=complex(zeros(nfft,blocks));
indices=[2:occupied/2+1 nfft-occupied/2+1:nfft];
symbols=randi(rs,[0 3],numel(indices),blocks);
grid(indices,:)=exp(1j*(pi/4+pi/2*symbols));
x=ifft(grid,nfft,1)*sqrt(nfft);
x=x(:); x=x(1:count);
x=x*0.7/max(abs(x));
end

function value=localSpectralACLR(x)
n=2^nextpow2(numel(x));
s=abs(fftshift(fft(double(x(:)),n))).^2;
f=(-n/2:n/2-1)'/n;
assigned=sum(s(abs(f)<=0.125));
adjacent=sum(s((abs(f)>=0.15)&(abs(f)<=0.275)));
value=10*log10(max(assigned,realmin)/max(adjacent,realmin));
end

function value=localSpectralACLRResidual(output,reference)
n=2^nextpow2(max(numel(output),numel(reference)));
signalSpectrum=abs(fftshift(fft(double(reference(:)),n))).^2;
errorSpectrum=abs(fftshift(fft(double(output(:)-reference(:)),n))).^2;
f=(-n/2:n/2-1)'/n;
assigned=sum(signalSpectrum(abs(f)<=0.125));
adjacent=sum(errorSpectrum((abs(f)>=0.15)&(abs(f)<=0.275)));
value=10*log10(max(assigned,realmin)/max(adjacent,realmin));
end

function value=localPAPR(x)
p=abs(double(x(:))).^2;
value=10*log10(max(p)/max(mean(p),realmin));
end

