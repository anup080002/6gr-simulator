function localTriggerFault(fault)
switch string(fault)
    case "device_conformance_claim"
        sixgr.rf.runtime.RFSpecificationProfile.resolve("rf_device_conformance");
    case {"missing_tx_power","missing_nf"}
        sixgr.rf.runtime.AbsolutePowerLedger.applyStage( ...
            struct("ReferencePlane","DAC_INPUT","TotalPower_dBm",0), ...
            NaN,0,0,"DAC_OUTPUT");
    case "cfo_no_signal"
        sixgr.rf.runtime.CFOAcquisitionEngine.estimateTone(zeros(64,1),1e6);
    case "cfo_ambiguity"
        n=(0:255)'; sixgr.rf.runtime.CFOAcquisitionEngine.estimateTone( ...
            exp(1j*2*pi*0.2*n),1e6,"AmbiguityLimitHz",100e3);
    case "timing_no_peak"
        sixgr.rf.runtime.TimingAcquisitionEngine.estimate(zeros(64,1),ones(16,1));
    case "sco_no_profile"
        sixgr.rf.runtime.RFChainConfiguration.validate(struct( ...
            "ProfileID","rf_impaired_research","SCOEnabled",true));
    case "phase_noise_no_mask"
        sixgr.rf.runtime.PhaseNoiseProfile.validate(struct());
    case "iq_no_calibration"
        sixgr.rf.runtime.IQImbalanceProfile.compensate(1,struct());
    case "pa_missing_coefficients"
        sixgr.rf.runtime.PAProfile.apply(1,struct());
    case "dpd_no_coefficients"
        sixgr.rf.runtime.DPDTrainer.apply(1,struct());
    case "adc_no_fullscale"
        sixgr.rf.runtime.ADCModel.quantize(1,struct("Bits",8, ...
            "Convention","signed_midtread"));
    case "implicit_agc"
        sixgr.rf.runtime.AGCState(struct(),1);
    case "invalid_blocker"
        sixgr.rf.runtime.BlockerScenario.validate(struct());
    case "evm_wrong_reference"
        sixgr.rf.runtime.EVMMeasurement.measure(1,1,struct());
    case "aclr_wrong_filter"
        sixgr.rf.runtime.ACLRMeasurement.measure(ones(32,1),1e6,struct());
    case "power_control_no_pathloss"
        state=sixgr.rf.runtime.UplinkPowerControlState(1);
        state.resolve(struct("Channel","PUSCH","Mu",0,"MRB",1, ...
            "MeasuredPathloss_dB",90,"PathlossSource","configured_snr", ...
            "P0_dBm",-80,"Alpha",0.8,"DeltaTF_dB",0,"PCMAX_dBm",23));
    case "stale_tpc"
        state=sixgr.rf.runtime.UplinkPowerControlState(2);
        state.applyTPC(1,1,1,"accumulation");
    case "unsupported_tuple"
        sixgr.rf.runtime.RFCapabilityProfile.resolve( ...
            "rf_impaired_research","not_a_feature");
    case "nonfinite_samples"
        sixgr.rf.runtime.ADCModel.quantize(NaN,struct("Bits",8, ...
            "FullScale",1,"Convention","signed_midtread"));
    otherwise
        error("RF:UnsupportedCombination","Unknown negative fault.");
end
end

