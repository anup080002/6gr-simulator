function summary=runRFFrontEndImpactAnalysis(varargin)
%RUNRFFRONTENDIMPACTANALYSIS Execute 64-family matched RF impact study.

p=inputParser;
p.addParameter("ExperimentMatrix",fullfile(pwd,"tests","vectors","rf", ...
    "rf_impact_experiment_matrix.csv"),@(v)ischar(v)||isstring(v));
p.addParameter("OutputDir",fullfile(pwd,"artifacts","rf_frontend_impact"), ...
    @(v)ischar(v)||isstring(v));
p.addParameter("SeedList",[11 23 47 89 131 197],@isnumeric);
p.addParameter("ConfidenceLevel",0.95,@(v)isnumeric(v)&&isscalar(v));
p.addParameter("Strict",true,@(v)islogical(v)||(isnumeric(v)&&isscalar(v)));
p.parse(varargin{:});
opt=p.Results;
matrixPath=string(opt.ExperimentMatrix);
outputDir=string(opt.OutputDir);
vectorRoot=string(fileparts(matrixPath));

if logical(opt.Strict)
    baseSummaryPath=fullfile(pwd,"artifacts","rf_frontend_phase", ...
        "rf_test_summary.csv");
    if exist(baseSummaryPath,"file")~=2
        error("RF:UnsupportedCombination", ...
            "Strict RF impact execution requires a passing base phase.");
    end
    base=readtable(baseSummaryPath,"Delimiter",",", ...
        "ReadVariableNames",true,"TextType","string");
    if isempty(base)||any(upper(string(base.Status))~="PASS")|| ...
            any(double(base.Failed)>0)||any(double(base.IncompletePoints)>0)
        error("RF:UnsupportedCombination", ...
            "Strict RF impact execution is blocked by the base phase.");
    end
end

evidence=sixgr.rf.runtime.RFImpactEvidenceBuilder.build( ...
    matrixPath,double(opt.SeedList),double(opt.ConfidenceLevel));
artifacts=sixgr.rf.runtime.RFImpactArtifactExporter.export( ...
    evidence,vectorRoot,outputDir);
summary=struct("Passed",logical(artifacts.Passed), ...
    "Strict",logical(opt.Strict),"Artifacts",artifacts, ...
    "Metadata",evidence.Metadata,"OutputDir",outputDir, ...
    "ExperimentCount",height(evidence.rf_impact_raw_trials), ...
    "PairCount",height(evidence.rf_impact_operating_points), ...
    "RuleCount",height(evidence.rf_impact_rule_evaluation), ...
    "ClaimRestriction","BOUNDED_RF_IMPACT_NOT_DEVICE_CONFORMANCE");
end
