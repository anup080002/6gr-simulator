classdef RFPlanningResult
%RFPLANNINGRESULT Fail-closed result factory for RF execution planning.

    methods(Static)
        function result = executable(profile, configuration)
            if ~isstruct(profile) || ~isfield(profile, "Executable") || ...
                    ~logical(profile.Executable)
                error("RF:UnsupportedProfile", ...
                    "RF planning requires an executable specification profile.");
            end
            if nargin < 2 || ~isstruct(configuration)
                error("RF:UnsupportedCombination", ...
                    "RF planning requires an explicit configuration structure.");
            end
            encoded = jsonencode(orderfields(configuration));
            result = struct( ...
                "Status", "EXECUTE", ...
                "Passed", true, ...
                "ProfileID", string(profile.ProfileID), ...
                "ExecutionClass", string(profile.ExecutionClass), ...
                "ClaimClass", string(profile.ClaimClass), ...
                "ClaimText", string(profile.ClaimText), ...
                "ConfigurationSHA256", string(sixgr.util.sha256Hex( ...
                    uint8(unicode2native(encoded, "UTF-8")))), ...
                "Reason", "");
        end

        function result = rejected(profileId, errorId, reason)
            if strlength(strtrim(string(errorId))) == 0 || ...
                    strlength(strtrim(string(reason))) == 0
                error("RF:UnsupportedCombination", ...
                    "Rejected RF plans require a typed error and reason.");
            end
            result = struct( ...
                "Status", "REJECT", ...
                "Passed", false, ...
                "ProfileID", string(profileId), ...
                "ExecutionClass", "", ...
                "ClaimClass", "NO_CLAIM", ...
                "ClaimText", "", ...
                "ConfigurationSHA256", "", ...
                "ErrorID", string(errorId), ...
                "Reason", string(reason));
        end
    end
end
