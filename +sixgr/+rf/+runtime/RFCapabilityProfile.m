classdef RFCapabilityProfile
%RFCAPABILITYPROFILE Resolve bounded RF feature support without claim drift.

    methods(Static)
        function result = resolve(profileId, feature)
            profileToken = lower(strtrim(string(profileId)));
            featureToken = lower(strtrim(string(feature)));
            if profileToken == "unsupported_rf_device_conformance" || ...
                    profileToken == "rf_device_conformance"
                result = sixgr.rf.runtime.RFCapabilityProfile.rejected( ...
                    profileToken, featureToken, "RF_DEVICE_CONFORMANCE", ...
                    "baseband_lls_cannot_certify_rf_device");
                return;
            end
            profile = sixgr.rf.runtime.RFSpecificationProfile.resolve(profileToken);
            known = sixgr.rf.runtime.RFCapabilityProfile.allFeatures();
            if ~any(featureToken == known)
                error("RF:UnsupportedCombination", ...
                    "RF feature '%s' is not in the bounded capability catalog.", featureToken);
            end
            supported = true;
            reason = "profile_selected_feature";
            if profile.ExecutionClass == "ideal_phy_strict"
                supported = any(featureToken == [ ...
                    "identity_chain","absolute_power","thermal_noise","evm", ...
                    "frequency_error","pusch_power_control","pucch_power_control", ...
                    "srs_power_control","prach_power_control"]);
                reason = sixgr.rf.runtime.RFCapabilityProfile.chooseReason( ...
                    supported, "ideal_profile_selected_feature", ...
                    "impairment_disabled_in_ideal_profile");
            elseif profile.ExecutionClass == "rf_conformance_emulation"
                supported = ~any(featureToken == ["cfr","dpd","rf_device_certification"]);
                reason = sixgr.rf.runtime.RFCapabilityProfile.chooseReason( ...
                    supported, "bounded_emulation_profile_feature", ...
                    "not_in_bounded_emulation_profile");
            elseif profile.ExecutionClass == "rf_impaired_research"
                supported = featureToken ~= "rf_device_certification";
                reason = sixgr.rf.runtime.RFCapabilityProfile.chooseReason( ...
                    supported, "research_profile_selected_feature", ...
                    "device_certification_forbidden");
            end
            if supported
                outcome = "EXECUTE";
            else
                outcome = "REJECT";
            end
            result = struct( ...
                "ProfileID", profileToken, ...
                "Feature", featureToken, ...
                "Supported", logical(supported), ...
                "ActualOutcome", outcome, ...
                "ClaimClass", string(profile.ClaimClass), ...
                "Reason", reason);
        end
    end

    methods(Static, Access=private)
        function result = rejected(profile, feature, claimClass, reason)
            result = struct("ProfileID", string(profile), ...
                "Feature", string(feature), "Supported", false, ...
                "ActualOutcome", "REJECT", "ClaimClass", string(claimClass), ...
                "Reason", string(reason));
        end

        function value = chooseReason(condition, whenTrue, whenFalse)
            if condition
                value = string(whenTrue);
            else
                value = string(whenFalse);
            end
        end

        function features = allFeatures()
            features = [ ...
                "identity_chain","absolute_power","thermal_noise","static_cfo", ...
                "cfo_drift","timing_offset","sample_clock_offset","phase_noise", ...
                "common_lo_phase_noise","frequency_flat_iq", ...
                "frequency_selective_iq","dc_lo_leakage","memoryless_pa", ...
                "memory_pa","cfr","dpd","dac","lna_filter","agc","adc", ...
                "blocker","receiver_intermod","reciprocal_mixing","evm", ...
                "frequency_error","aclr","sem_obue","carrier_leakage", ...
                "pusch_power_control","pucch_power_control","srs_power_control", ...
                "prach_power_control","multi_chain_covariance", ...
                "impairment_interactions","rf_device_certification"];
        end
    end
end
