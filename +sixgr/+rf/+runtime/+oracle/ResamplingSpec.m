classdef ResamplingSpec
%RESAMPLINGSPEC Pure-math SCO count, drift and timestamp reference.
    methods(Static)
        function result=expected(sampleRateHz,scoPpm,inputSamples, ...
                initialTimingSamples)
            values=double([sampleRateHz scoPpm inputSamples initialTimingSamples]);
            if any(~isfinite(values))||sampleRateHz<=0||inputSamples<1|| ...
                    inputSamples~=round(inputSamples)||1+scoPpm*1e-6<=0
                error("RFOracle:ResamplingInvalid", ...
                    "Resampling reference inputs are invalid.");
            end
            ratio=1+scoPpm*1e-6;
            outputSamples=max(1,floor((inputSamples-1)/ratio)+1);
            result=struct("RateRatio",ratio, ...
                "InputSamples",inputSamples,"OutputSamples",outputSamples, ...
                "CumulativeDrift_samples",inputSamples*(ratio-1), ...
                "LastInputTimestamp_s",(initialTimingSamples+ ...
                (inputSamples-1)*ratio)/sampleRateHz);
        end
    end
end
