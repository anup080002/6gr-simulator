classdef FrequencyErrorMeasurement
%FREQUENCYERRORMEASUREMENT Receiver-derived residual frequency estimate.

    methods(Static)
        function result=measure(reference,observed,sampleRateHz, ...
                referencePlane)
            plane=sixgr.rf.runtime.RFReferencePlane.validate(referencePlane);
            x=double(reference(:)); y=double(observed(:));
            if numel(x)~=numel(y)||numel(x)<3||any(~isfinite(x))|| ...
                    any(~isfinite(y))||~(isscalar(sampleRateHz)&& ...
                    isfinite(sampleRateHz)&&sampleRateHz>0)|| ...
                    sum(abs(x).^2)<=eps
                error("RF:FrequencyMeasurementInvalid", ...
                    "Frequency-error measurement inputs are invalid.");
            end
            phase=unwrap(angle(y.*conj(x)));
            n=(0:numel(phase)-1).';
            fit=[n ones(size(n))]\phase;
            estimate=fit(1)*sampleRateHz/(2*pi);
            residual=phase-([n ones(size(n))]*fit);
            result=struct("FrequencyError_Hz",estimate, ...
                "PhaseIntercept_rad",fit(2), ...
                "ResidualPhaseRMS_rad",sqrt(mean(residual.^2)), ...
                "ReferencePlane",plane, ...
                "Source","reference_phase_slope_receiver_measurement");
        end
    end
end
