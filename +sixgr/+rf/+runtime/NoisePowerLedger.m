classdef NoisePowerLedger
%NOISEPOWERLEDGER Friis cascade and thermal-noise accounting.

    methods(Static)
        function result = cascade(gain_dB,nf_dB,bandwidthHz,temperatureK)
            gain_dB = double(gain_dB(:));
            nf_dB = double(nf_dB(:));
            if isempty(gain_dB) || numel(gain_dB)~=numel(nf_dB) || ...
                    any(~isfinite(gain_dB)) || any(~isfinite(nf_dB)) || ...
                    any(nf_dB<0) || ~(isscalar(bandwidthHz) && ...
                    isfinite(bandwidthHz) && bandwidthHz>0) || ...
                    ~(isscalar(temperatureK) && isfinite(temperatureK) && ...
                    temperatureK>0)
                error("RF:NoiseCascadeInvalid", ...
                    "Noise cascade requires finite gain/NF stages, ENBW and temperature.");
            end
            gains = 10.^(gain_dB/10);
            factors = 10.^(nf_dB/10);
            cumulative = factors(1);
            cumulativeFactors = zeros(size(factors));
            cumulativeFactors(1)=cumulative;
            precedingGain = gains(1);
            for stage=2:numel(factors)
                cumulative = cumulative+(factors(stage)-1)/precedingGain;
                cumulativeFactors(stage)=cumulative;
                precedingGain=precedingGain*gains(stage);
            end
            nfTotal_dB=10*log10(cumulative);
            % The bounded RF vector contract uses the conventional
            % -174 dBm/Hz reference at 290 K.
            noisePower_dBm=-174+10*log10(bandwidthHz)+nfTotal_dB+ ...
                10*log10(temperatureK/290);
            result=struct( ...
                "CumulativeNF_dB",10*log10(cumulativeFactors), ...
                "CascadeNF_dB",nfTotal_dB, ...
                "NoisePower_dBm",noisePower_dBm, ...
                "Bandwidth_Hz",double(bandwidthHz), ...
                "Temperature_K",double(temperatureK), ...
                "Method","friis_with_explicit_enbw");
        end
    end
end
